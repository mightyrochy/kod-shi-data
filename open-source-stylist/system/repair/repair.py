"""Single-item high-res local repair — QIE-2511 crop-and-stitch (E-011, SYSTEM_DESIGN §7.4).

Regenerate ONE garment region to match its full-resolution reference, changing nothing outside the
garment mask. Locality is structural: QIE only ever sees the CROP (it cannot touch pixels it is not
given), and only the feathered garment mask is composited back into the base. The garment region itself
is regenerated by the QIE-2511 edit conditioned on (crop = image1, garment reference = image2), so the
result is reference-faithful — the property E-011 tests.

No InpaintModelConditioning: QIE-2511 is an edit model, not an inpaint model; crop+stitch is the
locality mechanism (the validated "crop-and-stitch" pattern, design §13).

    python -m system.repair.repair --base <img> --mask <region.png> --ref <garment.png> \
        --instruction "..." --out <repaired.png>
Needs ComfyUI live (:8000) with qwen_image_edit_2511. No colour words in the instruction (H-COLOR).
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

import cv2
import numpy as np

from system.workflows import fill_workflow, load_template

ROOT = Path(__file__).resolve().parents[2]
WORKING_MAX = 1024
_COLOR_WORDS = frozenset({
    "red", "blue", "green", "yellow", "orange", "purple", "pink", "brown", "black", "white", "gray",
    "grey", "navy", "beige", "cream", "tan", "olive", "lemon", "lime", "gold", "silver", "teal",
})


def _check_no_color(text: str) -> None:
    found = _COLOR_WORDS.intersection(re.findall(r"[a-z]+", text.lower()))
    if found:
        raise ValueError(f"Colour words in instruction: {sorted(found)} — colour comes from the reference image.")


def _round16(x: int) -> int:
    return max(16, int(round(x / 16) * 16))


def _bbox(fg: np.ndarray, pad_frac: float) -> tuple[int, int, int, int]:
    ys, xs = np.where(fg)
    y0, y1, x0, x1 = int(ys.min()), int(ys.max()), int(xs.min()), int(xs.max())
    py, px = int((y1 - y0) * pad_frac), int((x1 - x0) * pad_frac)
    H, W = fg.shape
    return max(0, y0 - py), min(H, y1 + py + 1), max(0, x0 - px), min(W, x1 + px + 1)


def stitch_and_measure(base, fg, bbox, edited, feather=9.0, change_thresh=12):
    """Feather-composite `edited` into `base` ONLY within the garment mask, and measure how much
    changed OUTSIDE the (dilated) mask. Pure + deterministic — this is the locality guarantee tested
    by system/tests/test_repair_locality.py. Returns (out_image, outside_mask_change_pct)."""
    y0, y1, x0, x1 = bbox
    crop_fg = fg[y0:y1, x0:x1]
    alpha = crop_fg.astype(np.float32)
    if feather > 0:
        alpha = cv2.GaussianBlur(alpha, (0, 0), feather)
    alpha = alpha[..., None]
    region = base[y0:y1, x0:x1].astype(np.float32)
    blended = edited.astype(np.float32) * alpha + region * (1.0 - alpha)
    out = base.copy()
    out[y0:y1, x0:x1] = np.clip(blended, 0, 255).astype(np.uint8)

    k = int(2 * feather + 1)
    dil = cv2.dilate(fg.astype(np.uint8) * 255,
                     cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (k, k))) > 127
    changed = np.abs(out.astype(int) - base.astype(int)).sum(axis=2) > change_thresh
    outside = ~dil
    outside_pct = round(100.0 * int((changed & outside).sum()) / max(1, int(outside.sum())), 3)
    return out, outside_pct


def _download_frame01(client, outputs: dict, prefix: str, dst: Path) -> Path:
    """QIE layered output: frame01 (the first saved image with the prefix) is the primary output
    (V-QIE-001)."""
    for node_out in outputs.values():
        for img in node_out.get("images", []):
            if img.get("filename", "").startswith(prefix):
                dst.write_bytes(client.download(img["filename"], img.get("subfolder", ""),
                                                img.get("type", "output")))
                return dst
    raise RuntimeError(f"no QIE output with prefix {prefix!r}")


def repair(base_path, mask_path, garment_ref_path, instruction: str, out_path,
           seed: int = 42, steps: int = 20, cfg: float = 2.5, pad_frac: float = 0.2,
           feather: float = 9.0, change_thresh: int = 12, working_max: int = WORKING_MAX,
           client=None) -> dict:
    """Crop-and-stitch QIE repair of one garment region. Returns a manifest incl. the locality %."""
    _check_no_color(instruction)
    base_path, mask_path, out_path = Path(base_path), Path(mask_path), Path(out_path)
    base = cv2.imread(str(base_path))
    if base is None:
        raise FileNotFoundError(base_path)
    H, W = base.shape[:2]
    mask = cv2.imread(str(mask_path), cv2.IMREAD_GRAYSCALE)
    if (mask.shape[1], mask.shape[0]) != (W, H):
        mask = cv2.resize(mask, (W, H), interpolation=cv2.INTER_NEAREST)
    fg = mask > 127
    if not fg.any():
        raise ValueError("empty region mask")

    y0, y1, x0, x1 = _bbox(fg, pad_frac)
    crop = base[y0:y1, x0:x1]
    crop_fg = fg[y0:y1, x0:x1]
    ch, cw = crop.shape[:2]
    scale = working_max / max(ch, cw)
    ww, wh = _round16(cw * scale), _round16(ch * scale)

    out_dir = out_path.parent
    out_dir.mkdir(parents=True, exist_ok=True)
    crop_w_path = out_dir / "repair_crop.png"
    cv2.imwrite(str(crop_w_path), cv2.resize(crop, (ww, wh), interpolation=cv2.INTER_CUBIC))

    if client is None:
        from system.clients.comfyui import ComfyUIClient
        client = ComfyUIClient()
    crop_ref = client.upload_image(crop_w_path)
    garm_ref = client.upload_image(Path(garment_ref_path))

    template = load_template("qie2511_edit")  # standard QIE edit (EmptySD3LatentImage),
    #   NOT the layered try-on latent (EmptyQwenImageLayeredLatentImage) which under-generates.
    filled = fill_workflow(template, {
        "__PERSON_IMAGE__": crop_ref, "__REF_IMAGE__": garm_ref,
        "__POSITIVE_PROMPT__": instruction, "__NEGATIVE_PROMPT__": "",
        "__WIDTH__": ww, "__HEIGHT__": wh, "__CFG__": cfg, "__SAMPLER__": "euler",
        "__SCHEDULER__": "simple", "__SEED__": seed, "__STEPS__": steps,
        "__OUTPUT_PREFIX__": "repair_edit", "__DENOISE__": 1.0,
    })
    outputs = client.poll(client.submit(filled), timeout=600.0)
    edited_w = _download_frame01(client, outputs, "repair_edit", out_dir / "repair_edit.png")
    client.free()

    edited = cv2.resize(cv2.imread(str(edited_w)), (cw, ch), interpolation=cv2.INTER_CUBIC)

    out, outside_pct = stitch_and_measure(base, fg, (y0, y1, x0, x1), edited, feather, change_thresh)
    cv2.imwrite(str(out_path), out)

    return {
        "out": str(out_path), "crop_bbox": [y0, y1, x0, x1], "work_res": [ww, wh],
        "outside_mask_change_pct": outside_pct,
        "params": {"seed": seed, "steps": steps, "cfg": cfg, "pad_frac": pad_frac, "feather": feather},
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", required=True)
    ap.add_argument("--mask", required=True)
    ap.add_argument("--ref", required=True)
    ap.add_argument("--instruction", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--steps", type=int, default=20)
    ap.add_argument("--cfg", type=float, default=2.5)
    ap.add_argument("--working-max", type=int, default=WORKING_MAX)
    args = ap.parse_args()
    import json
    print(json.dumps(repair(args.base, args.mask, args.ref, args.instruction, args.out,
                            seed=args.seed, steps=args.steps, cfg=args.cfg,
                            working_max=args.working_max), indent=2))


if __name__ == "__main__":
    main()
