ПІДПИСИ = ((b"\xff\xd8\xff", "jpeg"), (b"\x89PNG\r\n\x1a\n", "png"), (b"GIF87a", "gif"), (b"GIF89a", "gif"),
           (b"II*\x00", "tiff"), (b"MM\x00*", "tiff"), (b"BM", "bmp"))


# ── Файл маніфесту ───────────────────────────────────────────────────────────────────────────────

def читати_все(шлях=МАНІФЕСТ):
    """Файл маніфесту → {"кадри": {адреса: запис-список}, "службові": {магазин: {адреса: моделей}}}; файла нема — порожньо.
    «службові» — вердикт на день останнього зняття (фід читає його файлом поруч із `feed.py` — `писати_службові`, бо з каталогу службові
    картинки вже прибрано); складальник рахує вердикт заново з записів v1 і маніфесту (`службові`)."""
    if not os.path.exists(шлях):
        return {"кадри": {}, "службові": {}}
    with gzip.open(шлях, "rb") as f:
        д = json.loads(f.read().decode("utf-8"))
    if д.get("схема") != СХЕМА:
        raise ValueError("маніфест кадрів: схема %r, очікувалась %r" % (д.get("схема"), СХЕМА))
    return {"кадри": д["кадри"], "службові": д.get("службові", {})}


# Вердикт для БРАУЗЕРА (рядок 6371): модулів `zhnyvarka/` у пакеті Pyodide нема, тож `фід_фото` читає вердикт не з
# маніфесту, а з файлу поруч із `feed.py` (`фід_фото.читати_службові_кадри`), який пише `писати_службові`.
СЛУЖБОВІ = os.path.join(КОРІНЬ, "джерела", "каталог_службові_кадри.json.gz")


def писати_службові(вердикт, шлях=СЛУЖБОВІ):
    """Вердикт {магазин: {адреса: моделей}} → файл поруч із фідом: відсортовано, без mtime (однакові дані — однакові байти);
    через тимчасовий файл. Викликає `main` разом із записом маніфесту; без мережі — `--службові`."""
    тіло = json.dumps(вердикт, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
    тимч = шлях + ".tmp"
    with open(тимч, "wb") as сирий, gzip.GzipFile(fileobj=сирий, mode="wb", compresslevel=9, mtime=0) as f:
        f.write(тіло)
    os.replace(тимч, шлях)


def читати(шлях=МАНІФЕСТ):
    """Маніфест із диска → {адреса: запис-список}; файла нема — порожній."""
    return читати_все(шлях)["кадри"]


def писати(кадри, службові_вердикт=None, шлях=МАНІФЕСТ):
    """Маніфест на диск: відсортовано, без mtime — однакові дані дають однакові байти; через тимчасовий файл.
    `службові_вердикт` не дано — лишається той, що був у файлі."""
    if службові_вердикт is None:
        службові_вердикт = читати_все(шлях)["службові"]
    тіло = json.dumps({"схема": СХЕМА, "поля": list(ПОЛЯ), "службові": службові_вердикт, "кадри": кадри},
                      ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
    тимч = шлях + ".tmp"
    with open(тимч, "wb") as сирий, gzip.GzipFile(fileobj=сирий, mode="wb", compresslevel=9, mtime=0) as f:
        f.write(тіло)
    os.replace(тимч, шлях)


# ── Один кадр: тип за сигнатурою, розмір, хеші ──────────────────────────────────────────────────

def тип_за_сигнатурою(б):
    """Тип тіла за першими байтами (не за заголовком і не за розширенням): jpeg, png, gif, webp, avif, heic, tiff,
    bmp, svg, html; порожнє тіло — «порожньо», решта — «інше»."""
    if not б:
        return "порожньо"
    for підпис, назва in ПІДПИСИ:
        if б.startswith(підпис):
            return назва
    if б[:4] == b"RIFF" and б[8:12] == b"WEBP":
        return "webp"
    if б[4:12] == b"ftypavif":
        return "avif"
    if б[4:12] in (b"ftypheic", b"ftypheix", b"ftypmif1"):
        return "heic"
    голова = б[:512].lstrip().lower()
    if голова.startswith((b"<svg", b"<?xml")):
        return "svg"
    if голова.startswith((b"<!doctype", b"<html", b"<head", b"<body")):
        return "html"
    return "інше"


def _біти_у_гекс(біти):
    import numpy as np
    return np.packbits(біти.astype(np.uint8).ravel()).tobytes().hex()


def виміряти(тіло):
    """Байти картинки → (ш, в, dHash, aHash) або (0, 0, "", ""), коли PIL її не читає. dHash — 256 біт у 64 hex:
    знак різниці сусідніх пікселів сірого 17×16; aHash — 64 біти в 16 hex: «піксель світліший за середній» у сірому
    8×8; прозорість лягає на білий фон."""
    import numpy as np
    from PIL import Image
    Image.MAX_IMAGE_PIXELS = 300_000_000
    try:
        з = Image.open(io.BytesIO(тіло))
        ш, в = з.size
        if з.format == "JPEG":
            з.draft("RGB", (512, 512))                       # декодування вдесятеро швидше; хеш від цього не міняється
        з.load()
        if з.mode in ("RGBA", "LA", "P"):
            з = з.convert("RGBA")
            фон = Image.new("RGBA", з.size, (255, 255, 255, 255))
            з = Image.alpha_composite(фон, з)
        сіре = з.convert("L")
        d = np.asarray(сіре.resize((17, 16), Image.LANCZOS), dtype=np.int16)
        a = np.asarray(сіре.resize((8, 8), Image.LANCZOS), dtype=np.float64)
        return ш, в, _біти_у_гекс(d[:, 1:] > d[:, :-1]), _біти_у_гекс(a > a.mean())
    except Exception:                                       # noqa: BLE001 — не картинка / обірвана: хеша нема, статус лишається
        return 0, 0, "", ""


def зняти(адреса):
    """Один запит → запис маніфесту. Збій — запис зі статусом (HTTP-код чи «тайм-аут»/«мережа»), не виняток."""
    дата = datetime.date.today().isoformat()
    ч = urllib.parse.urlsplit(адреса)
    url = ч._replace(path=urllib.parse.quote(ч.path, safe="/%~:@!$&'()*+,;=")).geturl()
    запит = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": "image/avif,image/webp,image/*,*/*;q=0.8"})
    try:
        with urllib.request.urlopen(запит, timeout=ТАЙМАУТ) as в:
            статус, тіло = в.status, в.read(СТЕЛЯ_БАЙТІВ + 1)
    except urllib.error.HTTPError as п:
        return [п.code, "", 0, 0, "", "", "", 0, дата]
    except TimeoutError:
        return ["тайм-аут", "", 0, 0, "", "", "", 0, дата]
    except Exception:                                       # noqa: BLE001 — DNS, TLS, обрив: «мережа», не «мертвий»
        return ["мережа", "", 0, 0, "", "", "", 0, дата]
    if len(тіло) > СТЕЛЯ_БАЙТІВ:
        return [статус, "завелике", 0, 0, "", "", "", len(тіло), дата]
    тип = тип_за_сигнатурою(тіло)
    ш, в, d, a = виміряти(тіло) if тип not in ("svg", "html", "порожньо", "інше") else (0, 0, "", "")
    return [статус, тип, ш, в, hashlib.sha256(тіло).hexdigest(), d, a, len(тіло), дата]


class Шлюз:
    """Не частіше одного початку запиту на `ІНТЕРВАЛ_ХОСТА` секунд — спільний для потоків одного хоста."""

    def __init__(self):
        self._замок, self._наступний = threading.Lock(), 0.0

    def чекати(self):
        with self._замок:
            зараз = time.monotonic()
            мить = max(зараз, self._наступний)
            self._наступний = мить + ІНТЕРВАЛ_ХОСТА
        if мить > зараз:
            time.sleep(мить - зараз)


def хост(адреса):
    return urllib.parse.urlsplit(адреса).netloc.lower()


def пройти(адреси, кадри, перерва_зберегти=180, шлях=МАНІФЕСТ, друк=print):
    """Знімає `адреси` (яких ще нема в `кадри`), хости паралельно, кожен під своїм шлюзом; записує в `кадри` і
    кожні `перерва_зберегти` с — на диск (обрив прогону не губить зроблене)."""
    за_хостом = collections.defaultdict(list)
    for а in адреси:
        за_хостом[хост(а)].append(а)
    шлюзи = {х: Шлюз() for х in за_хостом}

    def робота(а):
        шлюзи[хост(а)].чекати()
        return а, зняти(а)

    пули = {х: ПІЛ.ThreadPoolExecutor(ПОТОКІВ_НА_ХОСТ) for х in за_хостом}
    майбутні = [пули[хост(а)].submit(робота, а) for а in адреси]
    всього, зроблено, збереження = len(майбутні), 0, time.monotonic()
    for м in ПІЛ.as_completed(майбутні):
        а, запис = м.result()
        кадри[а] = запис
        зроблено += 1
        if time.monotonic() - збереження > перерва_зберегти:
            писати(кадри, шлях=шлях); збереження = time.monotonic()
            друк("  знято %d з %d · у маніфесті %d" % (зроблено, всього, len(кадри)))
    for п in пули.values():
        п.shutdown()
    писати(кадри, шлях=шлях)
    return зроблено


# ── Рішення: службові картинки й дублі розміру ───────────────────────────────────────────────────

def _магазин(зап):
    return next((п[1] for п in зап["параметри"] if п[0] == "магазин"), "")


def _назва(зап):
    return (зап.get("назва") or зап["ід"]).strip().lower()


def _модель(зап):
    """Ключ моделі: артикул крамниці (кольори однієї моделі мають один артикул, хоч назви різні — «Сукня … КРЕМ»,
    «Сукня … ЧОРНА»), а без артикула — назва."""
    return (зап.get("артикул") or "").strip().lower() or _назва(зап)


def _скільки_моделей(записи_кадру):
    """Скільки різних моделей несуть ці записи: менше з двох лічб (за артикулом і за назвою) — де один із ключів
    розсипає одну модель на кілька (назви кольорів) чи зливає різні (однакові назви), хибний збіг не береться."""
    return min(len({_модель(з) for з in записи_кадру}), len({_назва(з) for з in записи_кадру}))


def придатний(е):
    """Запис маніфесту з хешем вмісту: завантажився (200) і прочитався як картинка."""
    return bool(е) and е[0] == 200 and bool(е[5]) and е[2] > 0 and е[3] > 0


def _порівняти(а, б):
    """Кадри `а`, `б` (записи маніфесту) — один знімок у різних розмірах: ті самі байти, або схожий вміст, та сама
    пропорція й помітно різна площа (`ДУБЛЬ_*`)."""
    if а[4] == б[4]:
        return True
    ра, рб = а[2] / а[3], б[2] / б[3]
    пл = max(а[2] * а[3], б[2] * б[3]) / min(а[2] * а[3], б[2] * б[3])
    if abs(ра - рб) / max(ра, рб) > ДОПУСК_ПРОПОРЦІЇ:
        return False
    d, a_ = bin(int(а[5], 16) ^ int(б[5], 16)).count("1"), bin(int(а[6], 16) ^ int(б[6], 16)).count("1")
    if пл >= ДУБЛЬ_ПЛОЩА:
        return d <= ДУБЛЬ_DHASH and a_ <= ДУБЛЬ_AHASH
    return d <= ДУБЛЬ_ТОЙ_САМИЙ_РОЗМІР and a_ <= ДОПУСК_AHASH           # перекодування (jpg ↔ webp) того самого розміру


def _збіг_із_насінням(вузли, насіння):
    """Вузли й насіння — [(ключ, dhash, ahash, пропорція)] → {ключ вузла: індекс насіння, на яке він схожий найбільше}:
    dHash ≤ `ДОПУСК_DHASH` із 256, aHash ≤ `ДОПУСК_AHASH` із 64, пропорція в `ДОПУСК_ПРОПОРЦІЇ`."""
    import numpy as np
    if not вузли or not насіння:
        return {}
    таблиця = np.array([bin(і).count("1") for і in range(256)], dtype=np.uint8)
    слова = lambda рядки, к: np.array([[int(р[і:і + 16], 16) for і in range(0, к, 16)] for р in рядки], dtype=np.uint64)  # noqa: E731
    d, ds = слова([в[1] for в in вузли], 64), слова([в[1] for в in насіння], 64)
    a, as_ = слова([в[2] for в in вузли], 16)[:, 0], слова([в[2] for в in насіння], 16)[:, 0]
    р, рs = np.array([в[3] for в in вузли]), np.array([в[3] for в in насіння])
    вихід = {}
    крок = max(1, 400_000 // max(1, len(насіння)))
    for з in range(0, len(вузли), крок):
        до = min(len(вузли), з + крок)
        в_d = таблиця[(d[з:до, None, :] ^ ds[None, :, :]).view(np.uint8)].reshape(до - з, len(насіння), 32).sum(2)
        в_a = таблиця[(a[з:до, None] ^ as_[None, :]).view(np.uint8)].reshape(до - з, len(насіння), 8).sum(2)
        відн = np.abs(р[з:до, None] - рs[None, :]) / np.maximum(р[з:до, None], рs[None, :])
        ок = (в_d <= ДОПУСК_DHASH) & (в_a <= ДОПУСК_AHASH) & (відн <= ДОПУСК_ПРОПОРЦІЇ)
        for r in np.nonzero(ок.any(1))[0].tolist():
            найближче = int(np.argmin(np.where(ок[r], в_d[r], 10 ** 6)))
            вихід[вузли[з + r][0]] = найближче
    return вихід


def службові(записи, кадри):
    """Службові кадри: {магазин: {адреса: [на скількох моделях стоїть вміст, [ід записів-власників]]}}.

    Докази: (1) ті самі БАЙТИ (sha256) на ≥ `СЛУЖБОВА_МОДЕЛЕЙ` різних моделях однієї крамниці — насіння; (2) кадр, що
    збігається зі змістом насіння за хешем вмісту (той самий знімок іншого розміру: 50×50 й 110×110 того самого лого).
    Лише збіг хешів без насіння службовим не робить — виміряно: dHash/aHash самі зливали різні речі на світлому тлі
    (джинси трьох відтінків, чорні туфлі) в один «кластер» на сотні моделей, і справжні фото речей пішли б геть.
    Власник знімка свій кадр зберігає: (а) модель, чий кадр у ≥ `ВЛАСНИК_ПЛОЩІ` разів більший за кадри решти групи
    (мініатюри її фото в чужих галереях); (б) записи, де цей кадр ПЕРШИЙ, коли таких не більше `ВЛАСНИКІВ_НАЙБІЛЬШЕ`
    (власне головне фото речі, що крамниця ще й виставила в «схожих» чужих товарів); лого й банер першими стоять на
    сотнях записів — власників нема, кадр знімається всюди."""
    за_крамницею = collections.defaultdict(lambda: collections.defaultdict(list))      # магазин → адреса → записи
    for з in записи:
        for а in dict.fromkeys(з["кадри"]):
            if придатний(кадри.get(а)):
                за_крамницею[_магазин(з)][а].append(з)
    вихід = {}
    for м, адреси in за_крамницею.items():
        за_байтами = collections.defaultdict(list)                 # sha256 → записи (за всіма адресами з цими байтами)
        for а, зз in адреси.items():
            за_байтами[кадри[а][4]] += зз
        насіння_sha = {ш for ш, зз in за_байтами.items() if _скільки_моделей(зз) >= СЛУЖБОВА_МОДЕЛЕЙ}
        if not насіння_sha:
            continue
        вузол = lambda а: (а, кадри[а][5], кадри[а][6], кадри[а][2] / кадри[а][3])           # noqa: E731
        насіння = {}                                                # sha256 → адреса-представник
        for а in sorted(адреси):
            if кадри[а][4] in насіння_sha:
                насіння.setdefault(кадри[а][4], а)
        список = [(ш, а) for ш, а in насіння.items()]
        великі = lambda а: min(кадри[а][2], кадри[а][3]) >= МІН_СТОРОНА_ХЕШУ                  # noqa: E731
        збіг = _збіг_із_насінням([вузол(а) for а in sorted(адреси) if великі(а)],
                                 [вузол(а) for _, а in список if великі(а)])
        список_великих = [(ш, а) for ш, а in список if великі(а)]
        група = {}                                                  # адреса → sha насіння, до якого належить
        for а in sorted(адреси):
            if кадри[а][4] in насіння_sha:
                група[а] = кадри[а][4]
            elif а in збіг:
                група[а] = список_великих[збіг[а]][0]
        записи_групи, площа = collections.defaultdict(list), collections.defaultdict(dict)
        for а, ш in група.items():
            записи_групи[ш] += адреси[а]
            for з_ in адреси[а]:
                мод = _модель(з_)
                площа[ш][мод] = max(площа[ш].get(мод, 0), кадри[а][2] * кадри[а][3])
        власник = {}
        for ш, п in площа.items():
            перші = sorted(п.items(), key=lambda x: -x[1])
            if len(перші) >= СЛУЖБОВА_МОДЕЛЕЙ and перші[0][1] >= ВЛАСНИК_ПЛОЩІ * перші[1][1]:
                власник[ш] = перші[0][0]
        службові_м = {}
        for а, ш in група.items():
            n = _скільки_моделей(записи_групи[ш])
            if n < СЛУЖБОВА_МОДЕЛЕЙ or {_модель(з_) for з_ in адреси[а]} == {власник.get(ш)}:
                continue
            перші = [з_["ід"] for з_ in адреси[а] if з_["кадри"] and з_["кадри"][0] == а]
            службові_м[а] = [n, перші if len(перші) <= ВЛАСНИКІВ_НАЙБІЛЬШЕ else []]
        if службові_м:
            вихід[м] = службові_м
    return вихід


def без_дублів_розміру(галерея, кадри):
    """Адреси однієї галереї → без повторів знімка: група — на місці першого кадру, з адресою найбільшого (ш×в, далі
    байти). Кадри без хеша (не завантажились, svg) стоять як є."""
    групи = []                                              # [[адреси групи]]; стоять у порядку першого члена
    for а in галерея:
        е = кадри.get(а)
        if придатний(е):
            for г in групи:
                if придатний(кадри.get(г[0])) and _порівняти(кадри[г[0]], е):
                    г.append(а); break                      # noqa: E702
            else:
                групи.append([а])
        else:
            групи.append([а])
    return [max(г, key=lambda а: (кадри[а][2] * кадри[а][3], кадри[а][7]) if придатний(кадри.get(а)) else (0, 0))
            if len(г) > 1 else г[0] for г in групи]


def для_файлу(вердикт):
    """Вердикт для файлу маніфесту: {магазин: {адреса: моделей}} — лише кадри без власників (читач фіду `фід_фото`
    знімає їх з кадрів збагачення; кадр із власником — чиєсь головне фото, його вимір лишається)."""
    return {м: {а: в[0] for а, в in д.items() if not в[1]} for м, д in вердикт.items() if any(not в[1] for в in д.values())}


def рішення(записи, кадри):
    """(кадри_після, лічби): {ід запису: [адреси, що лишаються]} і числа — службових кадрів (записів/адрес), дублів розміру,
    речей, що лишились без жодного кадру. Чиста функція: записи й маніфест не міняються."""
    служба = службові(записи, кадри)
    після, л = {}, collections.Counter()
    for з in записи:
        сл = {а: в for а, в in служба.get(_магазин(з), {}).items() if з["ід"] not in в[1]}      # власник свій кадр лишає
        галерея = list(dict.fromkeys(з["кадри"]))            # повтор тієї ж адреси в галереї — той самий кадр
        л["повторів адреси"] += len(з["кадри"]) - len(галерея)
        л["службових"] += sum(а in сл for а in галерея)
        л["записів зі службовим"] += any(а in сл for а in галерея)
        чисті = [а for а in галерея if а not in сл]
        без = без_дублів_розміру(чисті, кадри)
        л["дублів розміру"] += len(чисті) - len(без)
        л["записів із дублем"] += len(чисті) != len(без)
        л["було"] += len(з["кадри"]); л["лишилось"] += len(без)                  # noqa: E702
        л["без кадрів після"] += bool(з["кадри"]) and not без
        після[з["ід"]] = без
    return після, dict(л)


