def адреси_записів(записи, магазини=None):
    """Різні адреси кадрів записів, у порядку появи; `магазини` обмежує крамницями."""
    return list(dict.fromkeys(а for з in записи if not магазини or _магазин(з) in магазини for а in з["кадри"]))


def main(argv=None):
    for потік in (sys.stdout, sys.stderr):
        try:
            потік.reconfigure(encoding="utf-8", errors="replace")
        except Exception:                                    # noqa
            pass
    ап = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ап.add_argument("--зняти", action="store_true", help="завантажити нові адреси каталогу й дописати в маніфест")
    ап.add_argument("--магазин", nargs="+", help="лише ці крамниці (ключ «магазин» запису)")
    ап.add_argument("--перепробувати", action="store_true", help="узяти й ті адреси, що в маніфесті без завантаження")
    ап.add_argument("--файл", default=МАНІФЕСТ, help="інший файл маніфесту (проби поза репозиторієм)")
    ап.add_argument("--межа", type=int, help="не більше стільки адрес (проба)")
    ап.add_argument("--вердикт", action="store_true", help="що зніме складальник (без мережі); записує вердикт у маніфест")
    ап.add_argument("--службові", action="store_true", help="лише переписати вердикт маніфесту поруч із фідом (без мережі, без перерахунку)")
    а = ап.parse_args(argv)
    if а.службові:
        писати_службові(читати_все(а.файл)["службові"])
        print("вердикт → %s" % os.path.relpath(СЛУЖБОВІ, КОРІНЬ))
        return 0
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import складальник as С
    _, записи = С.читати_записи()
    кадри = читати(а.файл)
    if а.зняти:
        адреси = [x for x in адреси_записів(записи, а.магазин)
                  if x not in кадри or (а.перепробувати and not (кадри[x][0] == 200 and кадри[x][4]))]
        if а.межа:
            адреси = адреси[:а.межа]
        print("адрес до зняття: %d (у маніфесті вже %d)" % (len(адреси), len(кадри)))
        if адреси:
            print("знято: %d" % пройти(адреси, кадри, шлях=а.файл))
    if а.вердикт or а.зняти:
        вердикт = для_файлу(службові(записи, кадри))
        писати(кадри, вердикт, а.файл)
        if os.path.abspath(а.файл) == os.path.abspath(МАНІФЕСТ):
            писати_службові(вердикт)                            # браузер читає вердикт файлом поруч із фідом (рядок 6371)
    стан = collections.Counter(str(е[0]) if е[0] != 200 else "200 " + е[1] for е in кадри.values())
    print("маніфест: %d адрес · %s" % (len(кадри), dict(стан.most_common(12))))
    if а.вердикт or а.зняти:
        _, л = рішення(записи, кадри)
        print("рішення складальника: " + " · ".join("%s %d" % (к, v) for к, v in л.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
