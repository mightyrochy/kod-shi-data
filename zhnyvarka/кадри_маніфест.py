СХЕМА = "к2"
ПОЛЯ = ("статус", "тип", "ш", "в", "sha256", "dhash", "ahash", "байти", "дата")

СЛУЖБОВА_МОДЕЛЕЙ = 3          # §3.4: той самий вміст на ≥ 3 моделях крамниці — службова картинка
ДОПУСК_DHASH, ДОПУСК_AHASH = 3, 2      # бітів dHash із 256 і aHash із 64: той самий знімок у різних розмірах (0–2), не схожа річ
