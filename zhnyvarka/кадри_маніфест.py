# самої камери того самого розміру не зливаються (хіба байти ті самі).
ДУБЛЬ_DHASH, ДУБЛЬ_AHASH, ДУБЛЬ_ПЛОЩА = 22, 10, 1.15
ДУБЛЬ_ТОЙ_САМИЙ_РОЗМІР = 3              # dHash: той самий розмір, інше кодування (cultboutique `.jpg` і `.jpg.webp`)
МІН_СТОРОНА_ХЕШУ = 100                 # менші кадри (мініатюри, свотчі) за хешем не зіставляються: біле тло й силует збігаються у різних речей
ВЛАСНИКІВ_НАЙБІЛЬШЕ = 2                # записів, де кадр перший, не більше за стільки — вони власники кадру (див. `службові`)
ВЛАСНИК_ПЛОЩІ = 10                     # ш×в найбільшого кадру однієї моделі ≥ у стільки разів за кадри решти — вона власник знімка
