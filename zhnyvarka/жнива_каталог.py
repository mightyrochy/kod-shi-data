"""Цілі записи журналу обходу → записи v1; невдалі відповіді не стирають каталог."""
import argparse
import collections
import hashlib
import json
from pathlib import Path
import re
from urllib.parse import urlsplit, urlunsplit
import xml.etree.ElementTree as ET

import жниварка as ж
import складальник as с
from журнал_карток import прочитати


def адреса(url):
    """Зіставляє мовні версії тієї самої картки, зберігаючи параметри варіанта."""
    ч = urlsplit(url)
    шлях = re.sub(r"^/(?:ua|uk|ru|en)/", "/", ч.path).rstrip("/")
    return urlunsplit(("https", ч.netloc.lower().removeprefix("www."), шлях, ч.query, ""))


def чужа_мова(url):
    """Повертає істину для сторінки неукраїнської версії (`/ru/`, `/en/`): її не береться ні в новий запис, ні в оновлення."""
    return re.match(r"^/(?:ru|en)(?:/|$)", urlsplit(url).path) is not None


def перетворити(з, старий, категорія, дата, зайняті=frozenset()):
    """Оновлює власні поля свіжої картки зі збереженням ід, адреси запису та невиміряного складу."""
    вихід = dict(старий or {}, схема=с.СХЕМА, збирач="обхід", категорія=категорія)
    if not старий:
        вихід["адреса"] = з["url"]
    elif чужа_мова(старий["адреса"]) and з["url"] not in зайняті:
        вихід["адреса"] = з["url"]
    вихід["ід"] = старий["ід"] if старий else "ж53-" + hashlib.sha256(з["url"].encode()).hexdigest()[:20]
    for поле, ключ in (("назва", "назва"), ("виробник", "бренд"), ("артикул", "артикул"),
                       ("ціна", "ціна"), ("ціна_стара", "ціна_стара"), ("валюта", "валюта")):
        if з.get(ключ) is not None:
            вихід[поле] = str(з[ключ])
    вихід.setdefault("валюта", "UAH")
    вихід.setdefault("ціна", "0")
    вихід["доступність"] = ("true" if з["available"] else "false") if з.get("available") is not None else (старий or {}).get("доступність")
    вихід["кадри"] = з.get("фото") or (старий or {}).get("кадри", [])
    вихід["опис"] = з.get("опис")
    вихід["вихід"] = {"опис": "тег"} if вихід["опис"] else {}
    нові = []
    for ім, ключ in ж._ПАРАМИ:
        if ключ in ("склад", "склад_джерело", "склад_непевний", "склад_основа") and not з.get("склад"):
            continue
        значення = дата if ключ == "знято" else з.get(ключ)
        if isinstance(значення, list):
            значення = ", ".join(str(x) for x in значення)
        if значення is not None and значення != "":
            нові.append([ім, str(значення), "с"])
    нові += [["~" + ім, значення, "к"] for ім, значення in з.get("характеристики_сирі", []) if ім and значення]
    нові.append(["джерела_полів", json.dumps(з.get("джерела_полів", {}), ensure_ascii=False), "с"])
    замінювані = {ім for ім, _ in ж._ПАРАМИ} | {"матеріал_родина", "Склад", "склад_оновлення", "джерела_полів"}
    давні = [п for п in (старий or {}).get("параметри", []) if п[2] == "с" and п[0] not in замінювані]
    if старий and not з.get("склад"):
        давні += [п for п in старий["параметри"] if п[0] in ("Склад", "склад", "склад_джерело", "склад_непевний", "склад_основа")]
        if any(п[0] in ("Склад", "склад") for п in давні):
            нові.append(["склад_оновлення", "NOT_MEASURED_RETAINED", "с"])
    вихід["параметри"] = давні + нові
    return вихід


def зібрати(журнал, шапка, записи):
    """Зливає останні успішні картки за адресою; неповні та помилкові відповіді лише рахує."""
    за_адресою = {}
    for і, з in enumerate(записи):
        if адреса(з["адреса"]) not in за_адресою or not чужа_мова(з["адреса"]):
            за_адресою[адреса(з["адреса"])] = і
    зайняті = {з["адреса"] for з in записи}
    категорії = ET.fromstring(шапка["початок"] + шапка["кінець"]).findall(".//category")
    невідомо = next(к.get("id") for к in категорії if к.text in ("без розділу", "без категорії"))
    лічби = collections.Counter()
    for файл in sorted((Path(журнал) / "сирі").glob("*.jsonl")):
        останні = {з["url"]: з for з in прочитати(файл)[0]}
        for ряд in останні.values():
            if ряд.get("стан") != "картка":
                лічби[ряд.get("стан") or "без_стану"] += 1
                continue
            if not ряд.get("записи"):
                лічби["без_нових_полів"] += 1
            картки = ряд.get("записи", [])
            адреси = collections.Counter(адреса(з["url"]) for з in картки)
            for з in картки:
                if чужа_мова(з["url"]):
                    лічби["не_українська_версія"] += 1
                    continue
                if адреси[адреса(з["url"])] != 1:
                    лічби["варіант_без_окремої_адреси"] += 1
                    continue
                if not з.get("назва") or not з.get("url") or not з.get("фото"):
                    лічби["неповна_картка"] += 1
                    continue
                і = за_адресою.get(адреса(з["url"]))
                старий = записи[і] if і is not None else None
                новий = перетворити(з, старий, старий["категорія"] if старий else невідомо, ряд["дата"], зайняті)
                зайняті.add(новий["адреса"])
                if старий:
                    лічби["оновлено"] += новий != старий
                    записи[і] = новий
                else:
                    за_адресою[адреса(з["url"])] = len(записи)
                    записи.append(новий); лічби["додано"] += 1
    return шапка, записи, лічби


def main():
    """Друкує зміну каталогу; записує лише з явним параметром оператора."""
    ап = argparse.ArgumentParser(description=__doc__)
    ап.add_argument("--журнал", required=True)
    ап.add_argument("--записати", action="store_true")
    а = ап.parse_args()
    шапка, записи, лічби = зібрати(а.журнал, *с.читати_записи())
    print(dict(лічби), "записів", len(записи))
    if а.записати:
        с.писати_записи(шапка, записи)
        с.писати_xml(с.скласти(шапка, записи, с.кадри_маніфест.читати()))


if __name__ == "__main__":
    main()
