"""Відновлюваний обхід крамниць: повторює прохід виконавця, доки черга адрес кожної крамниці не вичерпана.

Журнал (корінь `--журнал`) лежить поза репозиторієм; повторний запуск продовжує з місця, де обірвався.
Після кожного циклу пише `обхід_стан.tsv`: на крамницю — адрес, результат, лишилось, стан і причина кодами.
"""
import argparse
import collections
from concurrent.futures import ThreadPoolExecutor
import csv
import os
from pathlib import Path
import signal
import subprocess
import sys
import time
from виконавець import ШАПКА_ЗВЕДЕННЯ, читати_рецепти
from json_прохід import завершено, прочитати_стан as json_стан, відновити
from журнал_проходу import прочитати_чергу, ЖурналПроходу, відбиток_рецепта
from журнал_карток import прочитати
from журнал_таблиці import прочитати as прочитати_таблицю, замінити, створити

ТЕКА = Path(__file__).resolve().parent
ШАПКА = ("домен", "стан_код", "причина_код", "адрес", "готово", "лишилось", "цикл", "підстава")


def результати(журнал, домен):
    """Рахує результат по останньому запису кожної адреси з jsonl крамниці (картка, заслон, збій…)."""
    файл = Path(журнал) / "сирі" / (домен + ".jsonl")
    останні = {}
    for з in прочитати(файл)[0]:
        останні[з["url"]] = з.get("стан") or "без_стану"
    return collections.Counter(останні.values())


def черга(журнал, домен):
    """Повертає (усього, виконано) або None, коли SQLite-черга невідома."""
    база = Path(журнал) / "проходи" / домен / "черга.sqlite3"
    підсумок = прочитати_чергу(база, Path(журнал) / "сирі" / (домен + ".jsonl"))
    return підсумок[:2] if підсумок is not None else None


def залишок(журнал, домен, ч, резерв=1):
    """Лишає незавершений пошук адрес до повтору, навіть коли поточна черга порожня або вся DONE."""
    база = Path(журнал) / "проходи" / домен / "черга.sqlite3"
    if база.is_file():
        підсумок = прочитати_чергу(база, Path(журнал) / "сирі" / (домен + ".jsonl"))
        if підсумок is None:
            return max(резерв, 1)
        загалом, готово, відомо = підсумок
        return max(загалом - готово, int(not відомо))
    if ч is None:
        return 0 if завершено(журнал, домен) else max(резерв, 1)
    return ч[0] - ч[1]


def причина(нотатка):
    """Називає причину лише за явним слідом у нотатці виконавця; здогадок нема — інакше UNKNOWN."""
    н = нотатка.lower()
    if "заслон" in н or "403" in н or "cloudflare" in н:
        return "BOT_CHALLENGE"
    if "sitemap +0" in н:
        return "EMPTY_SOURCE"
    if "стеля" in н:
        return "CEILING"
    if "timeout" in н or "тайм" in н:
        return "TIMEOUT"
    if "збій" in н:
        return "EXCEPTION"
    return "UNKNOWN"


def є_картки(журнал, домен, резерв=False):
    """Визначає наявність прийнятих карток за останніми записами, а без них — за збереженим підсумком."""
    стани = результати(журнал, домен)
    return стани.get("картка", 0) > 0 if стани else bool(резерв)


def виконано_в_журналі(журнал, домен, резерв=0):
    """Рахує виконані адреси json-сімейства накопичувально, а без записів бере збережений підсумок."""
    стани = результати(журнал, домен)
    return sum(стани.values()) if стани else резерв


def стан_рядка(домен, ряд, цикл, журнал):
    """Зводить останній рядок зведення виконавця й чергу в стан крамниці (CATALOG / WAIT) з причиною."""
    нотатка, карток = ряд["нотатка"], int(ряд["карток"] or 0)
    ч = черга(журнал, домен)
    адрес = ч[0] if ч else int(ряд["адрес_знайдено"] or 0)
    готово = ч[1] if ч else виконано_в_журналі(журнал, домен, int(ряд["відкрито"] or 0))
    адрес = max(адрес, готово)
    лишилось = залишок(журнал, домен, ч)
    в_каталозі = є_картки(журнал, домен, карток > 0)
    причина_код = причина(нотатка)
    return dict(домен=домен, стан_код="CATALOG" if в_каталозі else "WAIT",
                причина_код="" if в_каталозі and причина_код == "UNKNOWN" else причина_код,
                адрес=адрес, готово=готово, лишилось=лишилось, цикл=цикл, підстава=нотатка[:200])


def останні_рядки(зведення, з_рядка):
    """Читає цілі підсумки після фізичного курсора; для домену береться останній."""
    ряди, курсор = прочитати_таблицю(зведення, ШАПКА_ЗВЕДЕННЯ, ШАПКА_ЗВЕДЕННЯ[4:12], з_рядка)
    return {р["домен"]: р for р in ряди}, курсор


def прочитати_стан(журнал):
    """Читає цілі рядки TSV; обірваний або пошкоджений рядок відбудує наступний обхід."""
    стани = {}
    файл = Path(журнал) / "обхід_стан.tsv"
    числа = ("адрес", "готово", "лишилось", "цикл")
    for р in прочитати_таблицю(файл, ШАПКА, числа)[0]:
        for к in числа:
            р[к] = int(р[к])
        стани[р["домен"]] = р
    return стани


def узгодити_стан(журнал, магазини, стани):
    """Відбудовує підсумки з журналів перед рішенням пропустити завершену крамницю."""
    for д in магазини:
        ч = черга(журнал, д)
        кінець = завершено(журнал, д)
        if д not in стани and ч is None and not кінець and not (Path(журнал) / "сирі" / (д + ".jsonl")).is_file():
            continue
        давній = стани.get(д, {})
        готово = ч[1] if ч is not None else виконано_в_журналі(журнал, д, давній.get("готово", 0))
        адрес = ч[0] if ч is not None else max(готово, давній.get("адрес", 0))
        лишилось = залишок(журнал, д, ч, давній.get("лишилось", 1))
        стани[д] = dict(домен=д, стан_код="CATALOG" if є_картки(журнал, д,
                       давній.get("стан_код") == "CATALOG") else "WAIT",
                       причина_код=давній.get("причина_код", "UNKNOWN") if лишилось else "",
                       адрес=адрес, готово=готово, лишилось=лишилось, цикл=давній.get("цикл", 0),
                       підстава=давній.get("підстава", "") if лишилось else "завершення підтверджено журналом")
    return стани


def записати(журнал, стани):
    """Атомарно замінює TSV після fsync і закриття тимчасового файлу на тому самому диску."""
    for домен, стан in стани.items():
        if прочитати(Path(журнал) / "сирі" / (домен + ".jsonl"))[1]:
            стан["причина_код"] = "JOURNAL_CORRUPT"
            стан["підстава"] = "пошкоджені записи JSONL пропущено; підсумок лише за цілими записами"
    замінити(Path(журнал) / "обхід_стан.tsv", ШАПКА, (стани[д] for д in sorted(стани)))


def узгодити_рецепти(журнал, рецепти):
    """Перевіряє відбиток перед пропуском крамниці, зберігаючи її історію й цілі відповіді."""
    for р in рецепти:
        домен, підпис = р["домен"], відбиток_рецепта(р)
        база = Path(журнал) / "проходи" / домен / "черга.sqlite3"
        if база.is_file():
            прохід = ЖурналПроходу(Path(журнал) / "проходи", домен, підпис,
                                  картки=Path(журнал) / "сирі" / (домен + ".jsonl"))
            прохід.закрити()
        elif json_стан(журнал, домен) and json_стан(журнал, домен).get("підпис") != підпис:
            відновити(журнал, домен, підпис)


def вбити_процес(proc):
    """Примусово завершує дерево процесів."""
    if proc.poll() is not None:
        return
    try:
        if sys.platform == "win32":
            subprocess.call(["taskkill", "/F", "/T", "/PID", str(proc.pid)],
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        else:
            os.killpg(proc.pid, signal.SIGKILL)
    except Exception:
        pass
    try:
        proc.kill()
    except Exception:
        pass


def запустити_крамниці(cmd, магазини, паралельно, секунд_на_магазин, секунд_на_цикл):
    """Запускає окреме дерево процесів на крамницю з межею її часу й спільним кінцем циклу.

    Черга живе в батьківському процесі: синхронне зависання не знищує ще не запущені крамниці.
    """
    кінець = time.monotonic() + секунд_на_цикл

    def виконати(домен):
        """Звільняє місце наступній крамниці після завершення або примусового зупинення поточної."""
        таймаут = min(секунд_на_магазин, кінець - time.monotonic())
        if таймаут <= 0:
            return -1, True
        try:
            proc = subprocess.Popen(cmd + ["--магазини", домен, "--паралельно", "1"],
                                    start_new_session=sys.platform != "win32")
        except OSError:
            return 1, False
        try:
            return proc.wait(timeout=таймаут), False
        except subprocess.TimeoutExpired:
            вбити_процес(proc)
            proc.wait(timeout=5)
            return -1, True

    with ThreadPoolExecutor(max_workers=max(паралельно, 1)) as пул:
        return dict(zip(магазини, пул.map(виконати, магазини)))


def main(argv=None):
    """Крутить цикли виконавця; за відсутності прогресу пише причину, зберігаючи стан наявного каталогу."""
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    ап = argparse.ArgumentParser(description=__doc__)
    ап.add_argument("--журнал", required=True)
    ап.add_argument("--магазини", default="усі")
    ап.add_argument("--транспорт", default="http,браузер")
    ап.add_argument("--циклів", type=int, default=6)
    ап.add_argument("--стеля", type=int, default=300)
    ап.add_argument("--секунд-на-магазин", type=int, default=900)
    ап.add_argument("--паралельно", type=int, default=2)
    ап.add_argument("--секунд-на-цикл", type=int, default=None)
    ап.add_argument("--заглушка", default=os.environ.get("ZHNYVARKA_ЗАГЛУШКА", None))
    ап.add_argument("--оновити-каталог", action="store_true", help="цілі нові поля → записи v1 → каталог; черга кадрів рахується з нього")
    а = ап.parse_args(argv)
    Path(а.журнал).mkdir(parents=True, exist_ok=True)
    зведення = Path(а.журнал) / "зведення_жнив.tsv"
    _, ряд0 = останні_рядки(зведення, 0)

    магазини = перелік_крамниць(а)
    рецепти = читати_рецепти(ТЕКА / "рецепти.tsv")
    без_рецепта = (set(магазини) - {р["домен"] for р in рецепти}
                   if not а.заглушка and а.магазини.strip() in ("усі", "all", "") else set())
    if not а.заглушка:
        узгодити_рецепти(а.журнал, [р for р in читати_рецепти(ТЕКА / "рецепти.tsv") if р["домен"] in магазини])
    стани = узгодити_стан(а.журнал, магазини, прочитати_стан(а.журнал))
    for домен in без_рецепта:
        стани[домен] = dict(домен=домен, стан_код="WAIT", причина_код="NO_RECIPE", адрес=0,
                           готово=0, лишилось=1, цикл=0, підстава="увімкнено в реєстрі; рецепта обходу немає")
    магазини = [д for д in магазини if д not in без_рецепта]
    if стани:
        записати(а.журнал, стани)
        магазини = [д for д in магазини if д not in стани or
                    залишок(а.журнал, д, черга(а.журнал, д), стани[д]["лишилось"]) > 0]

    for цикл in range(1, а.циклів + 1):
        if not магазини:
            break
        партій = (len(магазини) + max(а.паралельно, 1) - 1) // max(а.паралельно, 1)
        таймаут_циклу = а.секунд_на_цикл if а.секунд_на_цикл is not None else (партій * а.секунд_на_магазин + 60)
        cmd = [sys.executable, str(ТЕКА / "виконавець.py"), "--журнал", а.журнал, "--без-огляду",
               "--рецепти", str(ТЕКА / "рецепти.tsv"),
               "--транспорт", а.транспорт, "--стеля", str(а.стеля),
               "--секунд-на-магазин", str(а.секунд_на_магазин)]
        if а.заглушка:
            cmd += ["--заглушка", а.заглушка]

        до_циклу = {}
        for д in магазини:
            ч = черга(а.журнал, д)
            до_циклу[д] = dict(готово=ч[1] if ч else виконано_в_журналі(а.журнал, д, стани.get(д, {}).get("готово", 0)))
        створити(зведення, ШАПКА_ЗВЕДЕННЯ)
        завершення = запустити_крамниці(cmd, магазини, а.паралельно, а.секунд_на_магазин, таймаут_циклу)
        код = next((к for к, _ in завершення.values() if к), 0)

        ряди, ряд0 = останні_рядки(зведення, ряд0) if зведення.is_file() else ({}, 0)
        наступні = []
        for д in магазини:
            _, таймаут_вийшов = завершення[д]
            if д in ряди:
                if таймаут_вийшов:
                    ряди[д]["нотатка"] += " | таймаут процесу крамниці"
                с = стан_рядка(д, ряди[д], цикл, а.журнал)
            else:
                # Крамниця без рядка у зведенні: межа часу процесу/циклу або аварійне завершення
                ч = черга(а.журнал, д)
                адрес = ч[0] if ч else (стани[д]["адрес"] if д in стани else 0)
                готово = ч[1] if ч else виконано_в_журналі(а.журнал, д, стани.get(д, {}).get("готово", 0))
                адрес = max(адрес, готово)
                лишилось = залишок(а.журнал, д, ч, стани.get(д, {}).get("лишилось", 1))
                причина_код = "TIMEOUT" if таймаут_вийшов else "збій"
                підстава = "таймаут крамниці або циклу обходу (виконавця зупинено)" if таймаут_вийшов else "виконавець не повернув рядка зведення"
                був_у_каталозі = є_картки(а.журнал, д, д in стани and стани[д]["стан_код"] == "CATALOG")
                с = dict(домен=д, стан_код="CATALOG" if був_у_каталозі else "WAIT",
                         причина_код=причина(причина_код),
                         адрес=адрес, готово=готово, лишилось=лишилось,
                         цикл=цикл, підстава=підстава)
            стани[д] = с
            if с["лишилось"]:
                if не_стоїть(до_циклу[д], с):
                    наступні.append(д)
                else:
                    if с["причина_код"] in ("", "UNKNOWN"):
                        с["причина_код"] = "NO_PROGRESS"
                    с["підстава"] = с["підстава"][:150] + " | немає нових виконаних адрес за цикл"
        записати(а.журнал, стани)
        print("цикл %d: код %d · крамниць %d → лишилось продовжувати %d" % (цикл, код, len(магазини), len(наступні)), flush=True)
        магазини = наступні

    if а.оновити_каталог:
        from жнива_каталог import зібрати
        import складальник as с
        шапка, записи, лічби = зібрати(а.журнал, *с.читати_записи())
        с.писати_записи(шапка, записи)
        с.писати_xml(с.скласти(шапка, записи, с.кадри_маніфест.читати()))
        print("каталог:", dict(лічби), flush=True)
        subprocess.run([sys.executable, str(ТЕКА.parent / "джерела/жнива_кадри.py"), "--галереї",
                        "--черга-вихід", str(Path(а.журнал) / "черга_галерей.tsv")], check=True)


def перелік_крамниць(а):
    """Повертає домени обходу без повторів і порожніх елементів (порожній аргумент виконавця означає всі)."""
    if а.магазини.strip() not in ("усі", "all", ""):
        return list(dict.fromkeys(x.strip().lower() for x in а.магазини.split(",") if x.strip()))
    рецепти = {р["домен"]: р for р in читати_рецепти(ТЕКА / "рецепти.tsv")}
    with open(ТЕКА / "магазини.tsv", encoding="utf-8") as ф:
        return [р["домен"] for р in csv.DictReader((р for р in ф if not р.startswith("#")), delimiter="\t")
                if р["стан"] == "увімкнено" and (р["домен"] not in рецепти or
                рецепти[р["домен"]]["транспорт"] in {x.strip() for x in а.транспорт.split(",")})]


def не_стоїть(було, є):
    """Перевіряє приріст виконаних адрес від початку поточного циклу."""
    if not було:
        return є["готово"] > 0
    return є["готово"] > було["готово"]


if __name__ == "__main__":
    main()
