"""ПЕРЕЗНЯТТЯ СКЛАДУ Й ОПИСУ КРАМНИЦЬ СТАРОГО ЗБИРАЧА В ЗАПИСАХ V1 — рядок 6801 дошки.

ЗАПУСК (з кореня репозиторію; мережа)
  python3 zhnyvarka/перезняти_склад_опис.py --магазин cooshwear.com --магазин vmma.com.ua            # лише зняти й порахувати
  python3 zhnyvarka/перезняти_склад_опис.py --магазин cooshwear.com --магазин vmma.com.ua --записати  # + переписати записи v1
  python3 zhnyvarka/складальник.py --зібрати                                                          # записи v1 → каталог XML

ЧОМУ НЕ ПОВНЕ ЖНИВО КРАМНИЦІ (так само, як у `перезняти_галереї.py`): записи cooshwear і vmma зібрав складальник 07.09, і
повне жнива дало б інші id, інший набір речей і втратило б службові поля запису (слот, силует, довжина, колір …). Тут
адреси беруться із самих записів, id, кадри й службові поля не рухаються, а міняється рівно те, що писав старий збирач
з чужим текстом сторінки: `Склад` (+ `склад_джерело`, `склад_непевний`, `склад_основа`), `опис`, характеристики крамниці («к»)
і `матеріал_родина`, якого нинішній код не пише (рядок 5677).

ЩО РОБИТЬ. Для кожного запису крамниці: тягне картку, читає її `жниварка.факти_з_картки` і `канонічний_запис` (опис — лише з
блоку, який сторінка підписала сама; склад — з підписаного блоку; пари — в межах блоку характеристик). Картка не відкрилась
чи не є карткою товару — запис НЕ чіпається, звіт називає це числом."""
import argparse, collections, concurrent.futures, os, sys, urllib.request
from urllib.parse import urlparse

ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ТУТ)
import жниварка as ж                                                        # noqa: E402
import складальник as с                                                     # noqa: E402

АГЕНТ = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"
СКЛАДОВІ = frozenset(("Склад", "склад", "склад_джерело", "склад_непевний", "склад_основа", "матеріал_родина"))


def домен(запис):
    return urlparse(запис.get("адреса") or "").netloc.lower().replace("www.", "")


def картка(адреса):
    """HTML картки або None (мережа не відповіла, не 200)."""
    try:
        with urllib.request.urlopen(urllib.request.Request(адреса, headers={"User-Agent": АГЕНТ}), timeout=40) as r:
            return r.read().decode("utf-8", "replace") if r.status == 200 else None
    except Exception:                                                       # noqa — звіт рахує, запис лишається
        return None


def оновити(запис):
    """Запис v1 → (новий запис, причина пропуску або None). Службові поля, кадри й id лишаються."""
    д = домен(запис)
    html = картка(запис["адреса"])
    if not html:
        return запис, "картка не відкрилась"
    ф = ж.факти_з_картки(html, запис["адреса"], ж.рецепт_селекторів(д))
    if not ф.get("є_товар") or ф.get("dom_помилка"):
        return запис, "не картка товару"
    з = ж.канонічний_запис(ф, {"домен": д, "платформа": None}, "картка")
    службові = [п for п in запис["параметри"] if п[2] == "с" and п[0] not in СКЛАДОВІ]
    нові = [["Склад", з["склад"], "с"]] if з.get("склад") else []
    нові += [[ім, з[ключ], "с"] for ім, ключ in (("склад_джерело", "склад_джерело"), ("склад_непевний", "склад_непевний"),
                                                 ("склад_основа", "склад_основа")) if з.get(ключ)]
    пари = [["~" + к.strip(" :"), v, "к"] for к, v in ф["характеристики_сирі"]]
    вихід = dict(запис["вихід"])                    # де опис стоїть у XML: «тег» лишається тегом, місце в параметрах — перед парами
    if not з.get("опис"):
        вихід.pop("опис", None)
    elif вихід.get("опис") != "тег":
        вихід["опис"] = len(службові) + len(нові)
    return dict(запис, опис=з.get("опис"), параметри=службові + нові + пари, вихід=вихід), None


def main(argv=None):
    ап = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ап.add_argument("--магазин", action="append", required=True, help="домен крамниці (можна кілька разів)")
    ап.add_argument("--записати", action="store_true", help="переписати записи v1 (без цього — лише звіт)")
    ап.add_argument("--потоки", type=int, default=3)
    a = ап.parse_args(argv)
    шапка, записи = с.читати_записи()
    черга = [і for і, з in enumerate(записи) if домен(з) in a.магазин]
    лічба = collections.defaultdict(collections.Counter)
    with concurrent.futures.ThreadPoolExecutor(a.потоки) as пул:
        for і, (новий, причина) in zip(черга, пул.map(lambda і: оновити(записи[і]), черга)):
            д, ст, нв = домен(записи[і]), записи[і], новий
            л = лічба[д]; л["записів"] += 1
            if причина:
                л[причина] += 1; continue
            пара = lambda з, ім: next((п[1] for п in з["параметри"] if п[0] == ім), None)
            л["оновлено"] += 1
            л["з описом: було"] += bool(ст.get("опис")); л["з описом: стало"] += bool(нв.get("опис"))
            л["зі складом: було"] += bool(пара(ст, "Склад")); л["зі складом: стало"] += bool(пара(нв, "Склад"))
            л["склад_непевний: стало"] += bool(пара(нв, "склад_непевний"))
            л["пар крамниці: було"] += sum(1 for п in ст["параметри"] if п[2] == "к")
            л["пар крамниці: стало"] += sum(1 for п in нв["параметри"] if п[2] == "к")
            записи[і] = нв
    for д, л in sorted(лічба.items()):
        print("%-16s %s" % (д, dict(л)))
    if a.записати:
        с.писати_записи(шапка, записи)
        print("записи v1 переписано: %s" % с.ЗАПИСИ)
    return 0


if __name__ == "__main__":
    sys.exit(main())
