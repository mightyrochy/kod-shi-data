# -*- coding: utf-8 -*-
"""ВЛИТТЯ ЖНИВ У КОРЕНЕВИЙ КАТАЛОГ — дописує офери нових магазинів у наявний XML.

ЗАПУСК
  python3 влиття_в_каталог.py --новий жнива_2026-09-18/каталог_повний.xml \
                              --каталог ../каталог_повний.xml.gz [--суходіл]
  python3 влиття_в_каталог.py --бриф ../джерела/каталог_brief.xml.gz --каталог ../каталог_повний.xml.gz

ЧОМУ ДОПИСУВАННЯ, А НЕ ПЕРЕЗБИРАННЯ З СИРИХ. Кореневий `каталог_повний.xml.gz`
(10 770 оферів, 43 магазини, `yml_catalog date 2026-09-07`) зібрано складальником,
якого в репозиторії НЕМА. Його підпис — `<name>код+ші</name><company>складання</company>
<url>local</url>`, категорії = СЛОТИ (1 сукня … 11 без розділу), параметри
`ранг_відбору`, `бал_інформації`, `поля`, `силует`, `тип`, `матеріал_родина`.
`жниварка.записати_каталог` пише інший підпис («Люстерко · …», версія жниварки,
github-адреса), категорії = шляхи розділів магазину і жодного з тих параметрів;
`виконавець.py` каталогу взагалі не пише (лише `сирі/*.jsonl`), хоча саме його
поняття (`бал_інформації`, `поля`) стоять у кореневому каталозі — тобто
складальник читав ЙОГО журнали. Журнали в гілці `zhnyva-data` є (47 файлів
`сирі/<домен>.jsonl.gz`), а складальника, який робить із них цей XML, у
репозиторії нема, і в історії git каталог — один коміт «Add files via upload».
Перезбирання означало б написати новий складальник: інші id, інші параметри,
усі сім полів складальника зникли б у 10 770 оферів. Тому — дописування.

ЩО ЗБЕРІГАЄТЬСЯ ПРИ ДОПИСУВАННІ: шапка, категорії, усі 10 770 наявних оферів
байт-у-байт, наскрізна нумерація `ж-NNNNN` (нові йдуть далі за останній).
ЩО ПЕРЕКЛАДАЄТЬСЯ: `categoryId` жниварки (шлях розділу магазину) → слот-категорія
кореневого каталогу, а сам шлях розділу лягає в `param name="категорія_магазину"`,
як у наявних оферів. Атрибут `group_id` не переноситься: у кореневому каталозі
його нема в жодного з 10 770 оферів, і асиметрія міняла б лічбу моделей
(`feed._ключ_моделі`) лише для нових магазинів.
ДЕДУПЛІКАЦІЯ за `url` — повторний запуск не подвоює магазин.

БРИФ (`--бриф`) — фікстура `build_артефакт.ФІД`: 427 оферів, байт-у-байт підмножина
кореневого, стратифікована по слотах (40 на слот, круговий обхід магазинів,
≤2 на магазин у великих слотах). Генератора в репозиторії нема, а на числах брифа
стоять зашиті очікування гейтів — тому наявні 427 НЕ чіпаються, а додаються лише
речі нових магазинів тим самим правилом: до 2 на (слот × магазин).
"""
import argparse, datetime, gzip, io, os, re, sys
import xml.etree.ElementTree as ET

НА_МАГАЗИН_У_СЛОТІ = 2          # бриф: щільність наявної вибірки у великих слотах


def байти(шлях):
    відкр = gzip.open if шлях.endswith(".gz") else io.open
    with відкр(шлях, "rb") as f:
        return f.read()


def читати(шлях):
    return ET.fromstring(байти(шлях))


def писати(дані, шлях):
    """ВСТАВКА В БАЙТИ, А НЕ ПЕРЕЗАПИС ДЕРЕВА.

    Перезбирання цілі через ET міняло б її навіть без жодного нового офера:
    XML-парсер нормалізує кінці рядків, і 166 `\\r\\n` в описах ставали `\\n`
    (виміряно на `каталог_повний.xml`), а `<currency … rate="1"/>` ставав
    `… rate="1" />`. Дані від цього не міняються — але «дописано 353 офери»
    перестає бути видимим у diff. Тому наявні байти лишаються як є, а нові
    офери вставляються перед `</offers>`.
    """
    відкр = (lambda ш: gzip.open(ш, "wb", compresslevel=9)) if шлях.endswith(".gz") else (lambda ш: io.open(ш, "wb"))
    with відкр(шлях) as f:
        f.write(дані)
    return len(дані)


def вставити(ціль_байти, нові_офери, дата=None):
    """Байти цілі + серіалізовані офери перед `</offers>`; `date` шапки — на дату збірки.

    Дату міняємо, бо її читає людина: каталог із речами, знятими 18.09, не має
    казати «07.09». Програмно її не читає ніхто (grep по `джерела/`), тож це
    єдина зміна поза новими оферами — решта байтів лишається як була.
    """
    межа = ціль_байти.rfind(b"</offers>")
    if межа < 0:
        raise ValueError("у цілі нема </offers> — це не YML-каталог")
    шматок = b"".join(ET.tostring(o, encoding="unicode").encode("utf-8") for o in нові_офери)
    голова = ціль_байти[:межа]
    if дата:
        голова = re.sub(br'(<yml_catalog date=")[^"]*(")', lambda m: m.group(1) + дата.encode("utf-8") + m.group(2),
                        голова, count=1)
    return голова + шматок + ціль_байти[межа:]


def _без_відступів(вузол):
    """ET.indent(space='') жниварки лишає '\\n' у text/tail — у кореневому каталозі їх нема."""
    for e in вузол.iter():
        if e.tail is not None and not e.tail.strip():
            e.tail = None
        if len(e) and e.text is not None and not e.text.strip():
            e.text = None
    return вузол


def _парам(offer, ім):
    for p in offer.findall("param"):
        if (p.get("name") or "") == ім:
            return (p.text or "").strip()
    return ""


def _шлях_категорії(корінь):
    """id категорії → повний шлях 'Батько / Дитина' (як у feed.шлях_кат)."""
    кат = {c.get("id"): ((c.text or "").strip(), c.get("parentId")) for c in корінь.iter("category")}
    def шлях(cid):
        імена, бачені = [], set()
        while cid and cid in кат and cid not in бачені:
            бачені.add(cid); імена.append(кат[cid][0]); cid = кат[cid][1]
        return " / ".join(reversed(імена))
    return шлях


def влити(шлях_каталогу, шлях_нового, вихід=None, статі=("жіноче", "унісекс")):
    ціль_байти = байти(шлях_каталогу)
    ціль = ET.fromstring(ціль_байти)
    нові = читати(шлях_нового)
    наявні = ціль.find(".//offers").findall("offer")
    слот_у_id = {(c.text or "").strip(): c.get("id") for c in ціль.iter("category")}
    без_розділу = слот_у_id["без розділу"]        # П19: колготи/шкарпетки/комплект слот-категорії не мають
    url_є = {(o.findtext("url") or "").strip() for o in наявні}
    номер = max(int(m.group(1)) for m in (re.match(r"ж-(\d+)$", o.get("id") or "") for o in наявні) if m)
    шлях_кат = _шлях_категорії(нові)

    додано, пропущено = [], {"дубль_url": 0, "стать": 0, "без_url": 0}
    for o in нові.iter("offer"):
        url = (o.findtext("url") or "").strip()
        стать = _парам(o, "стать")
        if not url:
            пропущено["без_url"] += 1; continue
        if url in url_є:
            пропущено["дубль_url"] += 1; continue
        if статі and стать and стать not in статі:
            пропущено["стать"] += 1; continue
        номер += 1
        новий = _без_відступів(ET.fromstring(ET.tostring(o, encoding="unicode")))
        # порядок і склад атрибутів — як у 10 770 наявних: лише id та available
        доступно = новий.get("available")
        новий.attrib = {"id": "ж-%05d" % номер}
        if доступно:
            новий.set("available", доступно)
        розділ = шлях_кат(новий.findtext("categoryId"))
        елем_кат = новий.find("categoryId")
        елем_кат.text = слот_у_id.get(_парам(новий, "слот")) or без_розділу
        if розділ and not _парам(новий, "категорія_магазину"):
            ET.SubElement(новий, "param", name="категорія_магазину").text = розділ
        url_є.add(url)
        додано.append(новий)
    if вихід:
        писати(вставити(ціль_байти, додано, _сьогодні()), вихід)
    return наявні, додано, пропущено


def _сьогодні():
    return datetime.datetime.now().strftime("%Y-%m-%d %H:%M")


def влити_бриф(шлях_брифа, шлях_каталогу, вихід=None):
    """Наявні офери брифа лишаються як є; з нових магазинів — до 2 на (слот × магазин)."""
    бриф_байти = байти(шлях_брифа)
    бриф = ET.fromstring(бриф_байти)
    повний = читати(шлях_каталогу)
    було = бриф.find(".//offers").findall("offer")
    є = {o.get("id") for o in було}
    магазини_брифа = {_парам(o, "магазин") for o in було}
    лічба, додано = {}, []
    for o in повний.iter("offer"):
        маг = _парам(o, "магазин")
        if o.get("id") in є or маг in магазини_брифа:
            continue
        ключ = (_парам(o, "слот"), маг)
        if лічба.get(ключ, 0) >= НА_МАГАЗИН_У_СЛОТІ:
            continue
        лічба[ключ] = лічба.get(ключ, 0) + 1
        додано.append(o)
    if вихід:
        писати(вставити(бриф_байти, додано, _сьогодні()), вихід)
    return було, додано


def main(argv=None):
    for потік in (sys.stdout, sys.stderr):
        try:
            потік.reconfigure(encoding="utf-8", errors="replace")
        except Exception:                                    # noqa
            pass
    ап = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ап.add_argument("--каталог", required=True, help="кореневий каталог_повний.xml(.gz) — ціль")
    ап.add_argument("--новий", help="каталог_повний.xml нових жнив (жниварка --зібрати)")
    ап.add_argument("--бриф", help="джерела/каталог_brief.xml.gz — доповнити новими магазинами")
    ап.add_argument("--вихід", default=None, help="куди писати (типово — поверх цілі)")
    ап.add_argument("--суходіл", action="store_true", help="лише порахувати, нічого не писати")
    a = ап.parse_args(argv)
    if a.новий:
        вихід = None if a.суходіл else (a.вихід or a.каталог)
        було, додано, проп = влити(a.каталог, a.новий, вихід)
        маг = {}
        for o in додано:
            маг[_парам(o, "магазин")] = маг.get(_парам(o, "магазин"), 0) + 1
        print("каталог: було %d оферів → стало %d (+%d)" % (len(було), len(було) + len(додано), len(додано)))
        for м, n in sorted(маг.items(), key=lambda x: -x[1]):
            print("  + %-24s %4d" % (м, n))
        print("пропущено: %s" % проп)
    if a.бриф:
        вихід = None if a.суходіл else (a.вихід or a.бриф)
        було, додано = влити_бриф(a.бриф, a.каталог, вихід)
        маг = {}
        for o in додано:
            маг[_парам(o, "магазин")] = маг.get(_парам(o, "магазин"), 0) + 1
        print("бриф: було %d оферів → стало %d (+%d)" % (len(було), len(було) + len(додано), len(додано)))
        for м, n in sorted(маг.items(), key=lambda x: -x[1]):
            print("  + %-24s %4d" % (м, n))
    return 0


if __name__ == "__main__":
    sys.exit(main())
