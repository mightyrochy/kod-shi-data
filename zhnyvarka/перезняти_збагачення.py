ПРОГІН = "рядок 132, %s" % time.strftime("%Y-%m-%d")


def _показаний_кадр(фото, тип, слот, модель):
    """Замість `обрати_кадр`: ціла — перший (показаний) кадр, запасна — другий власний."""
    придатні = [ф for ф in фото if ф.get("шлях") and not ф.get("заглушка")][:6]
    if not придатні:
        return None, None, {}, "усі фото — заглушки або не скачались"
    return 0, (1 if len(придатні) > 1 else None), {"1": "показаний"}, "кадр картки (міст_опис._фото_речі)"


def _помилка(причина, фото=None, модель=None):
    """Запис «не виміряно в цьому прогоні» — фід його не бере."""
    return dict(помилка="%s: %s" % (ПРОГІН, причина), фото=фото, версія=2, модель=модель,
                знято=time.strftime("%Y-%m-%d"), кадр="показаний", прогін=ПРОГІН)


def одна(o, кадри, модель):
    """Одна річ → (запис для фіду, короткий звіт)."""
    if not o.get("фото"):
        # Кадр картки тут — не знімок фіду, а запасний шлях `_фото_речі` (правило 4):
        # поле `фото` СТАРОГО запису. У 16 речей brenda це тайл «схожих товарів»
        # 293×440, тобто інша річ; рядок 126 зняв їм `picture`, бо речі в крамниці вже
        # нема. Міряти його — та сама хвороба рядка 124. `фото` тут порожнє навмисно.
        return _помилка("у фіді знімка нема (рядок 126 зняв picture: речі в крамниці вже нема); "
                        "запасний кадр старого запису — тайл «схожих товарів», не міряно"), "без picture"
    if not кадри:
        return _помилка("знімка нема — картка не малює жодного кадру, міряти нічого"), "знімка нема"
    фото = [ЖФ._скачати_фото(u, u, "r132-%s-" % (abs(hash(o["id"])) % 10 ** 8)) for u in кадри[:6]]
    ЖФ.позначити_одну(фото, lambda ф: 0)             # повтори вже відсіяв `_фото_речі`
    перше = фото[0]
    try:
        if перше.get("помилка") or перше.get("заглушка"):
            return (_помилка("показаний кадр не придатний (%s)" % (перше.get("помилка") or перше["заглушка"]),
                             кадри[0], модель), "кадр не придатний")
        зап = ЖЗ.обробити(dict(o, фото=кадри), фото, модель, показ=False)
        if "помилка" in зап or not зап.get("запис"):
            return _помилка(зап.get("помилка") or "обробка не дала запису", кадри[0], модель), "обробка"
        з = dict(зап["запис"], кадр="показаний", прогін=ПРОГІН, фото=кадри[0])
        return з, "маска %s %.2f · %s · згода %s" % ((зап.get("маска") or {}).get("джерело"),
                                                     (зап.get("маска") or {}).get("частка") or 0,
                                                     (з.get("колір_основний") or {}).get("слово"), з.get("впевненість"))
    except Exception as e:                           # збій однієї речі не валить прогін — він стає записом
        return _помилка("збій: %s" % str(e)[:160], кадри[0], модель), "збій"
    finally:
        ЖЗ.прибрати_кеш(фото)


def прогін(а):
    """Усі офери крамниці → `а.вихід` ({id: запис}), з продовженням."""
    оф = [o for o in F.читати_yml(а.каталог)[0] if o.get("магазин") == а.магазин]
    картки = {к["id"]: к for к in json.loads(МО.показ({"каталог": а.каталог, "речі": [o["id"] for o in оф]}))}
    готове = json.load(open(а.вихід, encoding="utf-8")) if (а.продовжити and os.path.exists(а.вихід)) else {}
    черга = [o for o in оф if o["id"] not in готове or "помилка" in готове[o["id"]]][:а.ліміт or None]
    print("%s: оферів %d, у черзі %d, SAM %s" % (а.магазин, len(оф), len(черга), bool(ЖМ._comfy())), flush=True)
    ЖЗ.обрати_кадр = _показаний_кадр
    замок, t0 = threading.Lock(), time.time()
    with ThreadPoolExecutor(а.потоки) as пул:
        майб = {пул.submit(одна, o, (картки.get(o["id"]) or {}).get("фото_усі") or [], а.модель): o for o in черга}
        for і, м in enumerate(as_completed(майб), 1):
            o = майб[м]
            з, звіт = м.result()
            with замок:
                готове[o["id"]] = з
                print("%s %3d/%d %s  %s" % (time.strftime("%H:%M:%S"), і, len(черга), o["id"], звіт), flush=True)
                if і % 20 == 0 or і == len(черга):
                    ЖЗ.записати_атомарно(готове, а.вихід)
    print("готово за %.1f хв: записів %d, з помилкою %d" % ((time.time() - t0) / 60, len(готове),
          sum(1 for з in готове.values() if "помилка" in з)), flush=True)


def злити(а):
    """Записи прогону → `каталог_збагачення.json.gz`: лише ід цієї крамниці, решта байт у байт."""
    ціль = os.path.join(ДЖЕРЕЛА, F.ЗБАГАЧЕННЯ_ІМ + ".gz")
    усе = json.loads(gzip.decompress(open(ціль, "rb").read()).decode("utf-8"))
    нове = json.load(open(а.вихід, encoding="utf-8"))
    суфікс = "@" + а.магазин
    for ід in [к for к in усе if к.endswith(суфікс) and к not in нове]:
        усе[ід] = _помилка("речі нема в почищеному каталозі — картки нема, не перезнято")
    усе.update({к: з for к, з in нове.items() if к.endswith(суфікс)})
    сирі = json.dumps(усе, ensure_ascii=False, separators=(",", ":"), sort_keys=True).encode("utf-8")
    with gzip.open(ціль + ".tmp", "wb", compresslevel=9) as f:
        f.write(сирі)
    os.replace(ціль + ".tmp", ціль)
    бр = [з for к, з in усе.items() if к.endswith(суфікс)]
    print("злито: записів %d, %s — %d, придатних для фіду %d" % (
        len(усе), а.магазин, len(бр), sum(1 for з in бр if F._збагачення_придатне(з))))


