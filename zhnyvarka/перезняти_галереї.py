# -*- coding: utf-8 -*-
"""ПЕРЕЖНИВЛЕННЯ ГАЛЕРЕЙ ОДНІЄЇ КРАМНИЦІ В НАЯВНОМУ КАТАЛОЗІ — рядок 126 дошки, 21.09.2026.

ЗАПУСК
  python3 перезняти_галереї.py --каталог ../каталог_повний.xml.gz --магазин brenda.ua \
          --знімки /tmp/brenda --звіт /tmp/brenda.json            # лише зняти й порахувати
  python3 перезняти_галереї.py ... --записати                      # + переписати <picture> в каталозі

ЧОМУ НЕ ПОВНІ ЖНИВА КРАМНИЦІ. Кореневий `каталог_повний.xml.gz` зібрано
складальником, якого в репозиторії нема (див. `влиття_в_каталог` — той самий
факт). Повний прогін `жниварка.зібрати_магазин` дав би ІНШІ id, інший набір
речей і втратив би сім параметрів складальника на 366 оферах — тобто зсув
стенда, який неможливо пояснити порядково. Тут адреси беруться з САМОГО
каталогу, id не рухається жодного, і міняється рівно одне поле — `<picture>`.
Скарга власника теж була рівно про нього: «Чому не має фотографії сукні у якої
на сайті є фотографія?» (`ж-01583@brenda.ua`).

ЗБАГАЧЕННЯ (`--збагачення`). Кадр, на якому модель міряла колір, крій, довжину й
матеріал, після пережнивлення може вже не належати речі — і тоді старий запис
збагачення стає БРЕХНЕЮ ПРО ЦЮ РІЧ, яку ніхто більше не спіймає: захист рядка
124 (`фід_каталог` відкидає вимір, знятий зі спільної картинки крамниці)
спирається на лічбу повторів у каталозі, а після заміни фото тайли «схожих»
перестають повторюватись — тобто лічба падає нижче `СПІЛЬНЕ_ФОТО_ТОВАРІВ` і
старий вимір ПРОХОДИТЬ. Виміряно на brenda: до пережнивлення чужим визнавався
331 кадр із 366, після — 1. Тому записи, чий кадр більше не стоїть у списку фото
речі, тут АНУЛЮЮТЬСЯ полем `помилка` — тим самим каналом, яким збагачення вже
каже «цієї речі я не бачила» (`фід_збагачення._збагачення_придатне` такий запис
не приймає, а `жнива_збагачення` ставить річ назад у чергу на перезняття).
Перезняти в цій сесії нема чим — живої vision-моделі тут нема, — і саме тому
позначка чесна, а не мовчазне старе значення.

ЩО РОБИТЬ. Для кожного офера крамниці: тягне його картку, читає фото
`жниварка.факти_з_картки` + `жниварка.чисті_фото` (з виправленням рядка 126 —
галерея з `href`/`style`/`srcset`/`data-*`, тайли «схожих товарів» відсічено) і
кладе в звіт «було / стало / скільки чужих тайлів відсічено». Речі, яка не
відкрилась або не дала жодного кадру, НЕ чіпає: мовчазної втрати фото тут не
буває — стара адреса лишається, а звіт називає причину числом.
"""
import argparse, collections, concurrent.futures, gzip, io, json, os, re, sys, time
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import жниварка as ж                                                        # noqa: E402

UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) "
      "Chrome/124.0.0.0 Safari/537.36")


def байти(шлях):
    """Вміст файла; `.gz` розпаковується."""
    відкр = gzip.open if шлях.endswith(".gz") else io.open
    with відкр(шлях, "rb") as f:
        return f.read()


def записати(дані, шлях):
    """Байти у файл; `.gz` пакується максимальним стисненням."""
    відкр = (lambda ш: gzip.open(ш, "wb", compresslevel=9)) if шлях.endswith(".gz") else (lambda ш: io.open(ш, "wb"))
    with відкр(шлях) as f:
        f.write(дані)
    return len(дані)


def _шлях_адреси(url):
    """(хост, шлях без кінцевих скісних) — щоб порівняти адресу запиту з кінцевою."""
    ч = str(url or "").split("://", 1)[-1].split("?")[0].split("#")[0].split("/", 1)
    return (ч[0].lower(), ("/" + (ч[1] if len(ч) > 1 else "")).rstrip("/"))


def офери_крамниці(корінь, магазин):
    """[(id, url, [фото])] для оферів названої крамниці, у порядку каталогу."""
    вих = []
    for o in корінь.findall(".//offer"):
        м = next((p.text for p in o.findall("param") if p.get("name") == "магазин"), None)
        if м != магазин:
            continue
        вих.append((o.get("id"), o.findtext("url") or "", [p.text for p in o.findall("picture") if p.text]))
    return вих


def зняти(url, тека, таймаут=45):
    """(код, html, кінцева адреса). Знімок і кінцева адреса кешуються поруч у теці.

    КІНЦЕВА АДРЕСА — НЕ ДРІБНИЦЯ (виміряно на brenda 21.09). Знятої речі крамниця
    не віддає 404: `https://brenda.ua/aninadin-1076` відповідає 200 і ГОЛОВНОЮ
    сторінкою. Без цієї перевірки жнива спокійно взяли б із неї банер
    `catalog/brenda/ban3-1170x566.jpg` і поклали б його як «фото речі» — тобто
    той самий дефект, від якого цей рядок дошки й лікує, тільки з іншого боку.
    """
    import requests
    кеш = os.path.join(тека, re.sub(r"[^a-zA-Z0-9]+", "_", url)[:150] + ".html") if тека else None
    супутник = (кеш + ".url") if кеш else None
    if кеш and os.path.exists(кеш) and os.path.getsize(кеш) > 2000:
        if супутник and os.path.exists(супутник):
            return 200, io.open(кеш, encoding="utf-8", errors="replace").read(), io.open(супутник, encoding="utf-8").read().strip()
        try:                                                  # знімок є, кінцевої адреси нема — доміряти дешево
            г = requests.head(url, headers={"User-Agent": UA}, timeout=таймаут, allow_redirects=True)
            io.open(супутник, "w", encoding="utf-8").write(г.url)
            return 200, io.open(кеш, encoding="utf-8", errors="replace").read(), г.url
        except Exception as e:                                # noqa: BLE001 — причина їде в звіт числом
            return 0, "%s: %s" % (type(e).__name__, str(e)[:120]), url
    try:
        в = requests.get(url, headers={"User-Agent": UA, "Accept-Language": "uk-UA,uk;q=0.9"}, timeout=таймаут)
    except Exception as e:                                    # noqa: BLE001 — причина їде в звіт числом
        return 0, "%s: %s" % (type(e).__name__, str(e)[:120]), url
    if в.status_code == 200 and кеш:
        io.open(кеш, "w", encoding="utf-8").write(в.text)
        io.open(супутник, "w", encoding="utf-8").write(в.url)
    return в.status_code, в.text, в.url


def одна(запис, тека):
    """Одна річ → рядок звіту: було / стало / чужих тайлів / причина, коли фото нема."""
    ід, url, було = запис
    код, тіло, кінцевий = зняти(url, тека)
    р = dict(ід=ід, url=url, код=код, було=було, стало=[], чужих=0, причина=None)
    if код != 200 or not тіло or len(тіло) < 2000:
        р["причина"] = "картка не відкрилась (код %s, %d Б)" % (код, len(тіло or ""))
        return р
    if _шлях_адреси(кінцевий) != _шлях_адреси(url):
        р["причина"] = "річ зникла з крамниці: редирект на %s" % кінцевий
        р["зникла"] = True
        return р
    ф = ж.факти_з_картки(тіло, url)
    р["чужих"] = ф.get("чужих_тайлів") or 0
    р["джерело"] = ф.get("фото_джерело")
    р["стало"] = ж.чисті_фото(ф.get("фото"), url, ф.get("артикул"))
    if not р["стало"]:
        р["причина"] = "на картці не знайдено жодного власного кадру"
    return р


def main(argv=None):
    """Розбір аргументів, прогін, звіт; `--записати` переписує `<picture>` у каталозі."""
    ап = argparse.ArgumentParser()
    ап.add_argument("--каталог", required=True)
    ап.add_argument("--магазин", required=True)
    ап.add_argument("--знімки", default="")
    ап.add_argument("--звіт", default="")
    ап.add_argument("--потоків", type=int, default=4)
    ап.add_argument("--стеля", type=int, default=0)
    ап.add_argument("--зниклим-зняти-фото", action="store_true",
                    help="речі, якої в крамниці вже нема, лишити БЕЗ <picture>: чесна арка замість чужої сукні")
    ап.add_argument("--збагачення", default="", help="каталог_збагачення.json.gz — анулювати записи, чий кадр більше не належить речі")
    ап.add_argument("--записати", action="store_true")
    а = ап.parse_args(argv)
    if а.знімки:
        os.makedirs(а.знімки, exist_ok=True)
    сирі = байти(а.каталог)
    корінь = ET.fromstring(сирі)
    записи = офери_крамниці(корінь, а.магазин)
    if а.стеля:
        записи = записи[:а.стеля]
    print("%s: оферів %d" % (а.магазин, len(записи)), flush=True)
    почато = time.time()
    with concurrent.futures.ThreadPoolExecutor(max_workers=а.потоків) as пул:
        звіт = list(пул.map(lambda з: одна(з, а.знімки), записи))
    змін = sum(1 for р in звіт if р["стало"] and р["стало"] != р["було"])
    print("знято за %.0f с; фото змінилось у %d речей; без кадру %d; не відкрилось %d"
          % (time.time() - почато, змін,
             sum(1 for р in звіт if not р["стало"] and р["код"] == 200),
             sum(1 for р in звіт if р["код"] != 200)), flush=True)
    print("коди: %s" % dict(collections.Counter(р["код"] for р in звіт)), flush=True)
    if а.звіт:
        io.open(а.звіт, "w", encoding="utf-8").write(json.dumps(звіт, ensure_ascii=False, indent=1))
    if а.записати:
        нове = {р["ід"]: р["стало"] for р in звіт if р["стало"]}
        if getattr(а, "зниклим_зняти_фото", False):
            # ЧОМУ ПОРОЖНЬО, А НЕ СТАРЕ (виміряно на brenda 21.09). У 16 речей
            # крамниця віддає замість картки головну сторінку — підтвердити їхні
            # знімки вже нічим, а знімки ці — тайли блоку «схожі товари», зняті
            # тим самим дефектом. Доти їх ховав незалежний детектор повторів; але
            # щойно РЕШТА каталогу крамниці дістала власні кадри, ті самі файли
            # перестали повторюватись (лічба впала з 5–9 до 1–3, тобто нижче
            # `СПІЛЬНЕ_ФОТО_ТОВАРІВ`) — і показ почав би малювати чужу сукню як
            # цю річ. «Знімка нема» — чесна відповідь, і в продукту вже є для неї
            # місце (колонка `знімка_нема`, рядок 124).
            нове.update({р["ід"]: [] for р in звіт if р.get("зникла")})
        текст, замін = переписати_picture(сирі.decode("utf-8"), нове, а.магазин)
        записати(текст.encode("utf-8"), а.каталог)
        print("у каталозі переписано <picture> у %d оферів" % замін, flush=True)
        if а.збагачення:
            анульовано = анулювати_збагачення(а.збагачення, записи, нове, а.магазин,
                                              {р["ід"]: р["причина"] for р in звіт if р["причина"]},
                                              {р["ід"] for р in звіт if р.get("зникла")})
            print("у збагаченні анульовано %d записів (кадр більше не належить речі)" % анульовано, flush=True)
    return 0


def _кадр(url):
    """Ім'я кадра без хоста й розміру — та сама одиниця «той самий знімок», що в жнивах."""
    return ж._кадр_і_площа(url)[0]


def анулювати_збагачення(шлях, записи, нове, магазин, причини, зниклі=()):
    """Записи збагачення, чий кадр не стоїть у списку фото речі → `помилка` з названою причиною.

    Критерій один і перевіряється по САМОМУ каталогу: кадр виміру має бути серед
    знімків цієї речі. Він ловить обидва випадки — і річ, якій пережнивлення дало
    власну галерею замість тайлів (кадр виміру зник зі списку), і річ, що зникла
    з крамниці (список лишився тайлами, тобто власного кадру ця модель не бачила
    ніколи). Значень старого виміру не лишаємо: поле, виведене з чужого знімка, —
    не факт про цю річ, а `помилка` ставить її назад у чергу на перезняття.
    """
    дані = json.loads(gzip.open(шлях, "rt", encoding="utf-8").read()) if шлях.endswith(".gz") \
        else json.loads(io.open(шлях, encoding="utf-8").read())
    сьогодні = time.strftime("%Y-%m-%d")
    n = 0
    for ід, url, було in записи:
        ключ = "%s@%s" % (ід, магазин)
        з = дані.get(ключ)
        if not з or "помилка" in з:
            continue
        фото = нове.get(ід) or було
        if ід not in зниклі and з.get("фото") and _кадр(з["фото"]) in {_кадр(x) for x in фото}:
            continue
        дані[ключ] = dict(версія=з.get("версія"), знято=сьогодні, фото=(фото or [None])[0],
                          модель=з.get("модель"),
                          помилка=("річ зникла з крамниці, власного кадру жнива не бачили: %s"
                                   % причини[ід]) if ід in зниклі else
                          "кадр виміру не належить речі: галерею перезнято %s (рядок 126)" % сьогодні)
        n += 1
    # ТА САМА СЕРІАЛІЗАЦІЯ, ЩО БУЛА: компактно й за ключами. Перевірено круговим
    # прогоном — незайманий файл після читання й запису збігається символ у символ,
    # тож у diff видно рівно анульовані записи, а не переформатування 12 223 рядків.
    сире = json.dumps(дані, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
    записати(сире, шлях)
    return n


_ОФЕР = re.compile(r"<offer\b[^>]*\bid=\"([^\"]+)\"[^>]*>(.*?)</offer>", re.S)
_PICTURE = re.compile(r"<picture>.*?</picture>", re.S)


def переписати_picture(текст, нове, магазин):
    """`<picture>` названих оферів → нові адреси; решта байтів каталогу не рухається.

    ЧОМУ ПО БАЙТАХ, А НЕ ЧЕРЕЗ ET (той самий доказ, що у `влиття_в_каталог.писати`):
    перезбирання дерева нормалізує `\\r\\n` в описах і `<currency … rate="1"/>`,
    і тоді «переписано 366 `<picture>`» перестає бути видимим у diff.
    """
    замін = [0]

    def офер(м):
        ід, старе_тіло = м.group(1), м.group(2)
        адреси = нове.get(ід)
        if адреси is None or ("<param name=\"магазин\">%s</param>" % магазин) not in старе_тіло:
            return м.group(0)
        перше = _PICTURE.search(старе_тіло)
        if not перше:
            return м.group(0)                      # офер без жодного <picture> — не наш випадок
        картинки = "".join("<picture>%s</picture>" % ж._xml_текст(a) for a in адреси)
        нове_тіло = старе_тіло[:перше.start()] + картинки + _PICTURE.sub("", старе_тіло[перше.start():])
        if нове_тіло == старе_тіло:
            return м.group(0)
        замін[0] += 1
        return м.group(0).replace(старе_тіло, нове_тіло, 1)

    return _ОФЕР.sub(офер, текст), замін[0]


if __name__ == "__main__":
    sys.exit(main())
