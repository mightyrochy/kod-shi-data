def розібрати_офер(тіло_атрибутів, внутр):
    """Один `<offer>` → запис схеми v1. Параметри — списком [ім, знач, рід] у порядку XML."""
    атр = _атрибути(тіло_атрибутів)
    зап = {"схема": СХЕМА, "ід": атр.pop("id"), "доступність": атр.pop("available", None)}
    if атр:
        raise ValueError("невідомі атрибути офера: %s" % sorted(атр))
    тег_у_поле = {т: п for п, т in ТЕГИ}
    параметри, кадри, опис, опис_тегом, порядок = [], [], None, False, []
    for тег, атрибути, текст in _ЕЛЕМЕНТ.findall(внутр):
        значення = _текст(текст)
        if тег in тег_у_поле:
            зап[тег_у_поле[тег]] = значення; порядок.append(тег)
        elif тег == "picture":
            кадри.append(значення)
        elif тег == "description":
            опис, опис_тегом = значення, True
        elif тег == "param":
            ім = _атрибути(атрибути)["name"]
            параметри.append([ім, значення, "с"])
        else:
            raise ValueError("невідомий тег офера: %s" % тег)
    початок = next((і for і, п in enumerate(параметри) if п[0] in ПОЧАТОК_СЛУЖБОВИХ), None)
    є_канал = any(п[0] == "канал" for п in параметри)
    for і, п in enumerate(параметри):
        # «к»: «~…» завжди; у жниварки — і все, що стоїть ПЕРЕД службовим хвостом
        if п[0].startswith("~") or (є_канал and початок is not None and і < початок
                                    and п[0] not in ПЕРЕД_ХВОСТОМ_СЛУЖБОВІ):
            п[2] = "к"
    вихід = {}
    if опис_тегом:
        вихід["опис"] = "тег"
    else:
        для_опису = [і for і, п in enumerate(параметри) if п[0] == "опис" and п[2] == "с"]
        if для_опису:
            і = для_опису[-1]; опис = параметри.pop(і)[1]; вихід["опис"] = і      # noqa: E702
    канонічний = [т for _, т in ТЕГИ if т in порядок]
    if порядок != канонічний:
        raise ValueError("порядок тегів офера %s не канонічний: %s" % (зап["ід"], порядок))
    адаптер = next((п[1] for п in параметри if п[0] == "адаптер"), None)             # запис адаптера каналу (рядок 5652)
    зап["збирач"] = ("адаптер " + адаптер) if адаптер else ("жниварка 18.09" if є_канал else "складальник 07.09")  # §3.1
    зап["кадри"], зап["опис"], зап["параметри"], зап["вихід"] = кадри, опис, параметри, вихід
    return зап


def розібрати(текст):
    """Весь XML каталогу → (шапка, записи). Шапка — усе до першого `<offer` і після останнього `</offer>`."""
    перший = текст.index("<offer ")
    кінець = текст.rindex("</offer>") + len("</offer>")
    шапка = {"схема": СХЕМА, "початок": текст[:перший], "кінець": текст[кінець:]}
    записи = [розібрати_офер(а, в) for а, в in _ОФЕР.findall(текст[перший:кінець])]
    return шапка, записи


def офер_xml(з, кадри=None):
    """Запис схеми v1 → `<offer>…</offer>` у форматі каталогу: теги, кадри, `<description>`, параметри.
    `кадри` — адреси `<picture>` після маніфесту (`кадри_маніфест.рішення`); не дано — усі кадри запису, як є."""
    атр = _атр("id", з["ід"])
    if з["доступність"] is not None:
        атр += _атр("available", з["доступність"])
    частини = ["<offer%s>" % атр]
    for поле, тег in ТЕГИ:
        if поле in з:
            частини.append("<%s>%s</%s>" % (тег, _екр(з[поле]), тег))
    частини.extend("<picture>%s</picture>" % _екр(к) for к in (з["кадри"] if кадри is None else кадри))
    місце = з["вихід"].get("опис")
    if місце == "тег":
        частини.append("<description>%s</description>" % _екр(з["опис"]))
    параметри = list(з["параметри"])
    if isinstance(місце, int):
        параметри.insert(місце, ["опис", з["опис"], "с"])
    for ім, знач, _ in параметри:
        частини.append("<param%s>%s</param>" % (_атр("name", ім), _екр(знач)))
    частини.append("</offer>")
    return "".join(частини)


def скласти(шапка, записи, маніфест=None):
    """Чиста функція: шапка + записи (+ маніфест кадрів) → текст XML каталогу. З маніфестом з `<picture>` зникають
    службові картинки крамниці й дублі розміру (рядок 5654); записи v1 лишаються сирими; без маніфесту — усі кадри."""
    після = кадри_маніфест.рішення(записи, маніфест)[0] if маніфест else {}
    return шапка["початок"] + "".join(офер_xml(з, після.get(з["ід"])) for з in записи) + шапка["кінець"]


def писати_записи(шапка, записи, шлях=ЗАПИСИ):
    with gzip.GzipFile(шлях, "wb", compresslevel=9, mtime=0) as f:
        for рядок in [шапка] + записи:
            f.write(json.dumps(рядок, ensure_ascii=False, separators=(",", ":")).encode("utf-8") + b"\n")


def читати_записи(шлях=ЗАПИСИ):
    with gzip.open(шлях, "rb") as f:
        рядки = [json.loads(р) for р in f.read().decode("utf-8").split("\n") if р]
    return рядки[0], рядки[1:]


def писати_xml(текст, шлях=КАТАЛОГ):
    with gzip.GzipFile(шлях, "wb", compresslevel=9, mtime=0) as f:
        f.write(текст.encode("utf-8"))


