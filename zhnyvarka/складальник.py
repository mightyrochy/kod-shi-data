def main(argv=None):
    for потік in (sys.stdout, sys.stderr):
        try:
            потік.reconfigure(encoding="utf-8", errors="replace")
        except Exception:                                    # noqa
            pass
    ап = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ап.add_argument("--з-каталогу", action="store_true", help="переписати записи v1 з нинішнього каталогу")
    ап.add_argument("--зібрати", action="store_true", help="записи v1 → каталог_повний.xml.gz")
    ап.add_argument("--знімок", action="store_true", help="зберегти лічби звіту як «попередню збірку»")
    ап.add_argument("--woo-знімок", metavar="ТЕКА", help="записи шести крамниць Woo → варіанти кольору зі знімка Store API "
                    "(`woo_знімок.py`); пише записи v1, збагачення, виміри кадрів і таблицю відповідності ж-номерів")
    ап.add_argument("--shopify-знімок", metavar="ТЕКА", help="записи крамниць Shopify → варіанти кольору зі знімка "
                    "`products.json` (`shopify_знімок.py`); пише ті самі файли, що й --woo-знімок")
    ап.add_argument("--проміжний", default=os.path.join(os.environ.get("TMPDIR", "/tmp"), "складальник_каталог.xml"))
    a = ап.parse_args(argv)
    поточний = байти_xml(КАТАЛОГ)
    if a.з_каталогу:
        шапка, записи = розібрати(поточний)
        писати_записи(шапка, записи)
        print("записано %d записів схеми %s → %s" % (len(записи), СХЕМА, ЗАПИСИ))
    шапка, записи = читати_записи()
    if a.woo_знімок:
        записи = _woo_варіанти(шапка, записи, a.woo_знімок)
    if a.shopify_знімок:
        записи = _shopify_варіанти(шапка, записи, a.shopify_знімок)
