def _ключ(ім):
    return ім.strip().lower()


def зібрати_лічби(записи, офери, кадри_після=None):
    """Скільки записів мають поле (записано) і скільки з них дійшло до оффера фіда (прочитано) — по збирачах.
    Ключі: «поле:<ім>» (перший рівень), «службове:<ім>», «характеристики (різні імена)», «кадрів знято» (кадри записів
    → кадри `<picture>` після маніфесту; лише коли дано `кадри_після`); значення {збирач: [з, ч]}."""
    за_ід = {о["id_жниварки"]: о for о in офери}
    лічба = collections.defaultdict(lambda: collections.defaultdict(lambda: [0, 0]))
    for з in записи:
        о, зб = за_ід.get(з["ід"]) or {}, з["збирач"]
        for поле, читач in ЧИТАЧ.items():
            if з.get(поле) not in (None, "", []):
                л = лічба["поле:" + поле][зб]; л[0] += 1; л[1] += bool(читач and читач(о))
        словник = о.get("параметри") or {}
        бачені = set()
        for ім, знач, рід in з["параметри"]:
            if рід == "с" and знач.strip() and ім not in бачені:
                бачені.add(ім)
                л = лічба["службове:" + ім][зб]; л[0] += 1; л[1] += bool((словник.get(_ключ(ім)) or "").strip())
        к = {_ключ(п[0]) for п in з["параметри"] if п[2] == "к"}
        л = лічба["характеристики (різні імена в записі)"][зб]; л[0] += len(к); л[1] += len(к & set(словник))
        л = лічба["записів"][зб]; л[0] += 1; л[1] += 1 if о else 0
        if кадри_після is not None:
            л = лічба["кадрів знято"][зб]; л[0] += len(з["кадри"]); л[1] += len(кадри_після[з["ід"]])
    return {к: dict(v) for к, v in лічба.items()}


def надрукувати_звіт(лічби, було=None, друк=print):
    """Таблиця «записано → прочитано» по збирачах, втрата і зміна від попередньої збірки (`було` — знімок лічб)."""
    збирачі = sorted({зб for v in лічби.values() for зб in v})
    друк("записано → прочитано фідом (оффер `фід_розбір.читати_yml` на зібраному XML, без чистки); «втрата» = записано − прочитано")
    друк("«характеристики» — дослівні пари крамниці: прочитано = імена, що лишились у словнику `параметри` оффера "
         "(дублі й регістр зливаються, перемагає остання); vendor/vendorCode/oldprice/currencyId — фід полем оффера не читає")
    друк("%-40s %s %8s %s" % ("поле", " ".join("%-22s" % зб for зб in збирачі), "втрата", "зміна проти попередньої збірки" if було else ""))
    for ключ in sorted(лічби, key=lambda к: (not к.startswith("поле:"), -sum(v[0] for v in лічби[к].values()), к)):
        клітини = [лічби[ключ].get(зб) for зб in збирачі]
        втрата = sum(з - ч for з, ч in (к for к in клітини if к))
        зміна = ""
        if було is not None:
            п = було.get(ключ)
            зміна = "нове" if п is None else ("" if п == лічби[ключ] else "було %s" % json.dumps(п, ensure_ascii=False))
        друк("%-40s %s %8d %s" % (ключ, " ".join("%-22s" % ("%d → %d" % tuple(к) if к else "—") for к in клітини), втрата, зміна))


