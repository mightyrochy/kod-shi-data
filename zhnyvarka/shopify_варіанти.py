# -*- coding: utf-8 -*-
"""SHOPIFY У ЗАПИСАХ V1: товар `products.json` → варіанти кольору (рядок 5653; проєкт `жниварка_логіка_2026-10-15.md` §3.1, §3.5).

Крамниці Shopify (wearme, honchstudio, jecomestudio, nyni) складалися сторінками: один запис на сторінку товару, колір —
здогадка зі слів (кінець назви, голова списку кольорів, слово артикула; рядки 5190, 5667). Тепер запис — ВАРІАНТ КОЛЬОРУ
товару, як в адаптері Woo (`woo_варіанти.py`): слово кольору — значення опції дослівно, кадри — зображення, прив'язані
платформою до його варіацій (`images[].variant_ids`), розміри й наявність — з `variants[].available`. Код слів не читає
(п.12): яка опція — колір, а яка — розмір, каже рецепт крамниці (`shopify_рецепти.tsv`, назва опції точним збігом).

ЗАПУСК (з кореня репозиторію)
  python3 zhnyvarka/shopify_знімок.py <тека>                     # мережа: products.json крамниць (локаль — з рецепта)
  python3 zhnyvarka/складальник.py --shopify-знімок <тека>       # знімок → записи v1 (+ таблиця відповідності ж-номерів)
  python3 zhnyvarka/складальник.py --зібрати                     # записи v1 → каталог_повний.xml.gz

ЯК РЕЧІ СТАЮТЬ ВАРІАНТАМИ (чиста функція `перебрати`; мережі нема, знімок — вхід).
  · Товар каталогу знаходиться за `handle` в адресі сторінки (`адреса` старого запису = `/products/<handle>`).
  · Українська версія (п.16): знімок береться з шляху рецепта (`/uk/products.json` у nyni, де без префікса сайт
    англійський), адреса запису — зі сторінкою тієї ж локалі. Решта крамниць українською без префікса.
  · Кольорів у товарі ≥ 2 → варіант на значення опції. Кадри варіанта — зображення, прив'язані ЛИШЕ до його варіацій
    (прив'язане до варіацій двох кольорів — спільне, нічиє); решта кадрів не має господаря, і код його не вгадує:
    розбір за виміром кольору — робота ноутбука (`жнива_кадри.py`, черга 5697). Колір, якому платформа кадру не
    прив'язала, лишається варіантом без кадру (як maxa в Woo), а товар, у якому не прив'язано жодному з кольорів,
    лишається сторінкою, як був. Колір один — кадри всі, як їх дала крамниця. Опції кольору в товарі нема (honchstudio: колір живе в назві) — один варіант, `Колір` старого запису
    лишається як був (код слова не вигадує й не губить), кадри всі.
  · Розміри — значення опції розміру дослівно (у верхньому регістрі, як у Woo); `розміри_в_наявності` — ті, чия
    варіація `available`.
  · ж-номер лишається за варіантом, чий кадр показувала стара картка (виміряний кадр жнив, інакше перший кадр; нема — перший варіант); решта
    кольорів — нові номери після найбільшого; номер ніколи не перевикористовується. `таблиця_відповідності_ж.tsv`
    каже, куди пішов кожен старий (у Shopify стовпець `слаг_кольору` — id першої варіації кольору, `id_товару_woo`
    і `модель_woo` — id товару Shopify).
  · Вимір кадру (`каталог_збагачення`, `каталог_кадри`) лишається, лише якщо виміряний кадр — той самий (адреса)
    серед кадрів варіанта; решта йде за чинним правилом «без виміру» і в чергу ноутбука (5697).
  · Розділювач стилю (рядок 6797): крамниця вписує в значення опції кольору слово стилю («Чорний[Смужка з вишивкою]»).
    Знак, яким вона його відділяє, каже рецепт (`розділювач_стилю`: відкривний і закривний знаки, «[]»). Це структура
    запису, не читання слів (п.12): код ділить значення за знаком і не розрізняє значень слів. До `Колір` іде все, що
    перед знаком; решта — окремий param `~Стиль` (дослівна характеристика крамниці). Кожне значення опції лишається
    окремим варіантом: «Чорний[Смужка]» і «Чорний[Цяточки]» мають свої кадри, колір у обох — «Чорний».
  · Товар поза записами каталогу (рядок 6799) — НОВИЙ запис: основа (слот, стать, бренд, опис) — з тих самих
    читачів жниварки, що й для сторінок (`жниварка.факти_shopify`, `канонічний_запис`, `гейти_речі`), далі той самий
    шлях варіантів. Опція кольору є — `Колір` її значення дослівно; опції нема (honchstudio, jecomestudio) — запису
    БЕЗ `Колір`: слова з назви код не бере й не вигадує (п.12), колір таких речей — вимір кадру ноутбуком (п.18,
    черга 5697). Нова річ без кадру з господарем, кольорів ≥ 2 — не береться (картка змішала б кольори, 6795)."""
import collections, csv, io, os, re, sys
from urllib.parse import unquote, urlparse

ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ТУТ)
import woo_варіанти as ва                                          # noqa: E402

РЕЦЕПТИ = os.path.join(ТУТ, "shopify_рецепти.tsv")
ЗБИРАЧ = "адаптер shopify v1"
КАНАЛ = "shopify:products.json"
# Старі параметри, які адаптер пише заново. `~size` — розміри ВСІЄЇ моделі зі сторінки, з наявністю не звірені.
ПЕРЕПИСАНІ = ва.ПЕРЕПИСАНІ | {"~size", "~Size"}
КОЛІР_СТАРОГО = frozenset(("Колір", "~Колір", "~колір", "~color", "~цвет"))
# Стать, з якою нова річ лишається в каталозі, — як у `влиття_в_каталог.влити`: чоловіче, дитяче й «невідомо» — не наш каталог.
# Типову стать крамниці каже поле `стать_типово` в `магазини.tsv`, не слово (п.12).
СТАТІ_КАТАЛОГУ = ("жіноче", "унісекс")
# `вихід["опис"]` нового запису: опис — param «опис» одразу після службових параметрів адаптера (фід читає опис із param,
# а не з `<description>`; клас Г5б), місце підставляє `_запис`.
ОПИС_ПАРАМОМ = "param"
_РУЧКА = re.compile(r"/products/([^/?#]+)")


def ручка(адреса):
    """`handle` товару з адреси сторінки (мовний префікс і запит не заважають)."""
    м = _РУЧКА.search(unquote(адреса or ""))
    return м.group(1).lower() if м else None


def читати_рецепти(шлях=РЕЦЕПТИ):
    """{домен: dict(шлях_знімка, шлях_сторінки, колір=[назви опцій], розмір=[назви опцій], стиль=«відкр+закр» чи "")}."""
    вих = {}
    with io.open(шлях, encoding="utf-8") as f:
        for р in csv.DictReader(f, delimiter="\t"):
            розділити = lambda с: [x.strip() for x in (с or "").split("|") if x.strip()]    # noqa: E731
            вих[р["домен"].strip().lower()] = dict(
                шлях_знімка=(р["шлях_знімка"] or "/products.json").strip(), шлях_сторінки=(р["шлях_сторінки"] or "").strip(),
                колір=розділити(р["опція_кольору"]), розмір=розділити(р["опція_розміру"]),
                стиль=(р.get("розділювач_стилю") or "").strip())
    return вих


def розділити_стиль(значення, знак):
    """Значення опції кольору → (колір, стиль) за знаком рецепта (`розділювач_стилю`: перший знак відкриває стиль,
    решта його закриває). Ділить лише за знаком, слів не читає (п.12): без знака в рецепті, без знака у значенні
    чи коли перед знаком нічого нема — (значення, None)."""
    if not знак or not значення or знак[0] not in значення:
        return значення, None
    колір, _, решта = значення.partition(знак[0])
    колір, стиль = колір.strip(), решта.strip()
    if знак[1:] and стиль.endswith(знак[1:]):
        стиль = стиль[:-len(знак[1:])].strip()
    return (колір, стиль or None) if колір else (значення, None)


def варіанти_shopify(т, рецепт):
    """Товар `products.json` → [dict] варіантів кольору або None (варіацій нема; кольорів ≥ 2, а кадр не прив'язано
    до жодного: тоді товар іде одним записом, як доти — кольори без кадрів нічого не дали б картці). Опції знаходить рецепт (назва
    опції точним збігом), слово кольору — значення опції дослівно.
    Поля варіанта: слово (None — опції кольору нема; стиль з нього відділено), стиль (None — знака стилю нема), кадри, кадри_джерело (shopify:variant_ids | shopify:images |
    None), розміри, розміри_в_наявності, розміри_джерело, є, ціна, ціна_стара, ід_варіацій, кольорів_у_товарі."""
    варіації = sorted(т.get("variants") or [], key=lambda в: в.get("position") or 0)
    if not варіації:
        return None
    ключ = {(о.get("name") or "").strip(): "option%d" % (о.get("position") or і + 1) for і, о in enumerate(т.get("options") or [])}
    ключ_к = next((ключ[н] for н in рецепт["колір"] if н in ключ), None)
    ключ_р = next((ключ[н] for н in рецепт["розмір"] if н in ключ), None)
    зображення = sorted((і for і in (т.get("images") or []) if і.get("src")), key=lambda і: і.get("position") or 0)
    групи = collections.OrderedDict()
    for в in варіації:
        групи.setdefault(в.get(ключ_к) if ключ_к else None, []).append(в)
    багато = len(групи) > 1
    колір_варіації = {в["id"]: к for к, вв in групи.items() for в in вв}
    власні = {к: [] for к in групи}
    for з in зображення:
        кольори = {колір_варіації[ід] for ід in з.get("variant_ids") or [] if ід in колір_варіації}
        if len(кольори) == 1:
            власні[next(iter(кольори))].append(з["src"])
    if багато and not any(власні.values()):
        return None                                     # кольорів ≥ 2, а платформа жодному не прив'язала кадр: товар лишається сторінкою
    вих = []
    for колір, вв in групи.items():
        усі, є = [], []
        for в in вв:
            р = (в.get(ключ_р) or "").strip() if ключ_р else ""
            if р:
                усі.append(р.upper())
                if в.get("available"):
                    є.append(р.upper())
        ціни = [float(в["price"]) for в in вв if в.get("price")]
        старі = [float(в["compare_at_price"]) for в in вв if в.get("compare_at_price")]
        кадри = власні[колір] if багато else [з["src"] for з in зображення]
        слово, стиль = розділити_стиль(колір, рецепт.get("стиль"))
        вих.append(dict(слово=слово, стиль=стиль, кадри=кадри, ціна=min(ціни) if ціни else None,
                        кадри_джерело=("shopify:variant_ids" if багато else "shopify:images") if кадри else None,
                        ціна_стара=max(старі) if старі else None, розміри=list(dict.fromkeys(усі)),
                        розміри_в_наявності=list(dict.fromkeys(є)), розміри_джерело="shopify:variants" if усі else None,
                        є=any(в.get("available") for в in вв), ід_варіацій=[в["id"] for в in вв], кольорів_у_товарі=len(групи)))
    return вих


def перебрати(записи, знімки, рецепти, збагачення, виміри_кадрів, сьогодні, ж=None, магазини=None):
    """Старі записи крамниць Shopify → записи варіантів. `знімки` — {домен: [товар products.json]}.
    Товар поза записами каталогу стає новим записом, коли дано `ж` (модуль `жниварка`) і `магазини` ({домен: рядок
    `магазини.tsv`}); без них такі товари лише рахуються (`поза_каталогом`).
    → (нові_записи, відповідність, збагачення, виміри_кадрів, звіт, черга). Вхідні словники не міняються."""
    нові_за_ід, відповідність, звіт, черга = {}, [], collections.OrderedDict(), []
    результат_зб, результат_км = dict(збагачення), dict(виміри_кадрів)
    наступний = max(ва._число(з["ід"]) for з in записи)
    слот_у_категорію = _категорії_слотів(записи)
    for домен in sorted(знімки):
        рецепт = рецепти[домен]
        старі = [з for з in записи if ва.магазин(з) == домен]
        за_ручкою = {ручка(з["адреса"]): з for з in старі}
        лічба = звіт[домен] = collections.Counter(старих=len(старі))
        знайдені = {т.get("handle", "").lower() for т in знімки[домен]}
        лічба["немає_в_api"] = sum(1 for з in старі if ручка(з["адреса"]) not in знайдені)
        for т in sorted(знімки[домен], key=lambda т: т["id"]):
            д = за_ручкою.get((т.get("handle") or "").lower())
            нова = д is None
            if нова:
                лічба["поза_каталогом"] += 1
                if ж is None:
                    continue
                д, причини = основа_нового(т, домен, рецепт, ж, магазини[домен], слот_у_категорію, сьогодні)
                if д is None:
                    лічба["нових_відхилено"] += 1
                    for п in причини:
                        лічба["відхилено: " + п.split(" (")[0]] += 1
                    continue
            варіанти = варіанти_shopify(т, рецепт)
            if not варіанти:
                лічба["нових_без_кадру_кольору" if нова else "лишились_як_були"] += 1
                continue
            старий_ід = "" if нова else д["ід"]
            зб = збагачення.get(старий_ід + "@" + домен)
            перший = зб.get("фото") if зб and зб.get("фото") else (д["кадри"][0] if not нова and д["кадри"] else None)
            власник = None if нова else next((в for в in варіанти if перший and ва.ключ_кадру(перший) in {ва.ключ_кадру(к) for к in в["кадри"]}), варіанти[0])
            база = "{0.scheme}://{0.netloc}".format(urlparse(д["адреса"])) + рецепт["шлях_сторінки"] + "/products/" + т["handle"]
            результат_зб.pop(старий_ід + "@" + домен, None)
            результат_км.pop(старий_ід + "@" + домен, None)
            лічба["нових_товарів"] += нова
            for в in варіанти:
                if в is власник:
                    ід = д["ід"]
                else:
                    наступний += 1
                    ід = "ж-%05d" % наступний
                зап = _запис(д, т, в, ід, база, сьогодні)
                нові_за_ід[ід] = зап
                лічба["записів_варіантів"] += 1
                лічба["нових_записів" if нова else "нових_ід"] += нова or ід != д["ід"]
                лічба["варіантів_без_кадру"] += not зап["кадри"]
                лічба["назву_змінено"] += not нова and зап["назва"] != д["назва"]
                відповідність.append((домен, старий_ід, ід, "новий запис (товар поза каталогом)" if нова else
                                      "лишено ід" if ід == д["ід"] else "новий ід (колір моделі)",
                                      str(т["id"]), str(в["ід_варіацій"][0]) if в["слово"] is not None else "", str(т["id"])))
                ва._вимір(збагачення, виміри_кадрів, результат_зб, результат_км, старий_ід, ід, зап, лічба, черга)
    результат = [нові_за_ід.pop(з["ід"], з) for з in записи]
    результат.extend(нові_за_ід[ід] for ід in sorted(нові_за_ід))
    return результат, відповідність, результат_зб, результат_км, звіт, черга


def _категорії_слотів(записи):
    """{слот: id категорії каталогу} — з наявних записів (слот і категорія — коди, слів тут нема)."""
    лічба = collections.defaultdict(collections.Counter)
    for з in записи:
        слот = next((п[1] for п in з["параметри"] if п[0] == "слот"), None)
        if слот:
            лічба[слот][з["категорія"]] += 1
    return {слот: к.most_common(1)[0][0] for слот, к in лічба.items()}


def основа_нового(т, домен, рецепт, ж, магазин, слот_у_категорію, сьогодні):
    """Товар `products.json` поза записами каталогу → (основа, []) чи (None, [причини]). Основа — те, що `_запис` бере
    зі старого запису `д`: схема, назва, виробник, валюта, категорія (слот каталогу), адреса, опис і службові
    параметри. Слот, стать, бренд, опис дають читачі жниварки на тих самих фактах, що й для сторінок
    (`канонічний_запис`); склад — ні: `склад_із` на вільному тексті опису тягне слова сусідніх речень («100% котон
    Колір: сіра *Будь ласка»), а опис їде моделі цілим; гейти — її ж (`гейти_речі`), крім «нема в наявності»: наявність на сайті річ із пулу не
    виключає (`ПРОДУКТ.md`, «Каталог і розбір»). `Колір` тут не пишеться: його дає лише опція кольору (`_запис`)."""
    адреса = "https://" + домен + рецепт["шлях_сторінки"] + "/products/" + т["handle"]
    ф = ж.факти_shopify(т, "https://" + домен)[0]
    ф["url"], ф["характеристики"] = адреса, {}
    з = ж.канонічний_запис(ф, dict(магазин, платформа="Shopify"), КАНАЛ)
    причини = [п for п in ж.гейти_речі(з) if not п.startswith("нема в наявності")]
    if not причини and з["слот"] not in слот_у_категорію:
        причини.append("слот без категорії каталогу")
    if not причини and з["стать"] not in СТАТІ_КАТАЛОГУ:
        причини.append("стать поза каталогом (%s)" % з["стать"])
    if причини:
        return None, причини
    параметри = [[ім, з[ім], "с"] for ім in ("слот", "слот_джерело", "стать", "стать_джерело") if з.get(ім)]
    if т.get("product_type"):
        параметри.append(["категорія_магазину", т["product_type"], "с"])
    параметри += [["магазин", домен, "с"], ["мова", з["мова"], "с"]]
    параметри += [["~" + ім, знач, "к"] for ім, знач in (("Тип", т.get("product_type")), ("Бренд", з.get("бренд")),
                  ("Теги", ", ".join(x for x in т.get("tags") or [] if isinstance(x, str)))) if знач]
    д = {"схема": "v1", "назва": з["назва"], "валюта": "UAH", "категорія": слот_у_категорію[з["слот"]], "адреса": адреса,
         "опис": з["опис"], "параметри": параметри, "вихід": {"опис": ОПИС_ПАРАМОМ} if з["опис"] else {}}
    if з.get("бренд"):
        д["виробник"] = з["бренд"]
    return д, []


def _запис(д, т, в, ід, база, сьогодні):
    """Запис варіанта: службові поля старого запису `д`, колір/кадри/розміри/наявність — адаптера."""
    багато = в["кольорів_у_товарі"] > 1
    адреса = база + (("?variant=%s" % в["ід_варіацій"][0]) if багато else "")
    параметри = [["id_магазину", str(т["id"]), "с"], ["канал", КАНАЛ, "с"], ["адаптер", "shopify v1", "с"],
                 ["наявність", "є" if в["є"] else "нема", "с"]]
    if в["слово"] is not None:
        параметри += [["Колір", в["слово"], "с"], ["колір_джерело", "shopify:options", "с"]]
    if в["стиль"]:
        параметри.append(["~Стиль", в["стиль"], "к"])
    параметри.append(["кадри_джерело", в["кадри_джерело"] or "невідомі", "с"])
    if в["розміри"]:
        параметри.append(["розміри", ", ".join(в["розміри"]), "с"])
        if в["розміри_в_наявності"]:
            параметри.append(["розміри_в_наявності", ", ".join(в["розміри_в_наявності"]), "с"])
        параметри.append(["розміри_джерело", в["розміри_джерело"], "с"])
    вихід = dict(д["вихід"])
    if вихід.get("опис") == ОПИС_ПАРАМОМ:
        вихід["опис"] = len(параметри)
    переписані = ПЕРЕПИСАНІ if в["слово"] is not None else ПЕРЕПИСАНІ - КОЛІР_СТАРОГО
    for ім, знач, рід in д["параметри"]:
        if ім in переписані:
            continue
        assert рід == "с" or ім.startswith("~"), (д["ід"], ім)
        параметри.append([ім, знач, рід])
    параметри.append(["знято", сьогодні, "с"])
    зап = {"схема": д["схема"], "ід": ід, "доступність": "true" if в["є"] else "false",
           "назва": " ".join((т.get("title") or "").split()) or д["назва"]}
    if "виробник" in д:
        зап["виробник"] = д["виробник"]
    зап["артикул"] = str(т["id"])
    ціна = ва._ціна(в["ціна"]) if в["ціна"] is not None else д.get("ціна")
    if ціна is not None:
        зап["ціна"] = ціна
    if в["ціна_стара"] and в["ціна"] is not None and в["ціна_стара"] > в["ціна"]:
        зап["стара_ціна"] = ва._ціна(в["ціна_стара"])
    зап["валюта"], зап["категорія"], зап["адреса"] = д["валюта"], д["категорія"], адреса
    зап["збирач"], зап["кадри"], зап["опис"] = ЗБИРАЧ, list(в["кадри"]), д["опис"]
    зап["параметри"], зап["вихід"] = параметри, вихід
    return зап


def _читати_рядки(шлях):
    if not os.path.exists(шлях):
        return None, []
    with io.open(шлях, encoding="utf-8") as f:
        рядки = [р.rstrip("\n").split("\t") for р in f]
    return рядки[0], рядки[1:]


def дописати_відповідність(рядки, домени, шлях=ва.ВІДПОВІДНІСТЬ):
    """Рядки Shopify у спільну таблицю: рядки цих крамниць замінюються, решта (Woo) лишається як є."""
    шапка, наявні = _читати_рядки(шлях)
    лишити = [р for р in наявні if р[0] not in домени]
    нові = [["" if x is None else str(x) for x in р] for р in рядки]
    with io.open(шлях, "w", encoding="utf-8", newline="\n") as f:
        f.write("\t".join(шапка) + "\n")
        for р in sorted(лишити + нові, key=lambda р: (р[0], р[1], р[2] or "")):
            f.write("\t".join(р) + "\n")


def дописати_чергу(рядки, домени, шлях=ва.ЧЕРГА, ідентифікатори=None):
    """Замінює чергу доменів або лише названих ід часткового знімка; решту зберігає."""
    шапка, наявні = _читати_рядки(шлях)
    лишити = [р for р in наявні if р[1] not in домени
              or (ідентифікатори is not None and р[0] not in ідентифікатори)]
    with io.open(шлях, "w", encoding="utf-8", newline="\n") as f:
        f.write("\t".join(шапка) + "\n")
        for р in sorted(лишити + [list(р) for р in рядки]):
            f.write("\t".join(р) + "\n")
