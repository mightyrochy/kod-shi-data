def норм_адреса(u):
    """Адреса сторінки для порівняння: без схеми, `www.`, слеша наприкінці й відсотків (кирилиця в slug)."""
    p = urlparse(unquote(u or "").strip().lower())
    return p.netloc.replace("www.", "") + re.sub(r"/+$", "", p.path)


def ключ_кадру(u):
    """Адреса кадру без запиту (`?v=…`) і схеми: «та сама адреса»."""
    p = urlparse(unquote(u or "").strip())
    return p.netloc.replace("www.", "").lower() + p.path


def слаг_адреси(адреса, рецепт):
    """Слаг терма кольору з запиту адреси варіанта (`?attribute_<таксономія>=<слаг>`, його пише `_запис`) для порівняння;
    None — адреса сторінки без варіанта."""
    зн = parse_qs(urlparse(адреса or "").query).get("attribute_" + рецепт["колір"]) if рецепт else None
    return unquote(зн[0]).lower() if зн else None


def магазин(з):
    return next((п[1] for п in з["параметри"] if п[0] == "магазин"), None)


def _параметр(з, ім):
    return next((п[1] for п in з["параметри"] if п[0] == ім), None)


def останній_номер(записи):
    """Найбільший ж-номер; ідентифікатори інших просторів імен номера не займають."""
    return max((int(м.group(1)) for з in записи if (м := re.fullmatch(r"ж-(\d+)", з["ід"]))), default=0)


def переможці_товарів(екз):
    """По одному екземпляру на товар (для лічби розмірів моделей)."""
    return list({е["ід_т"]: е for е in екз}.values())


def _ціна(x):
    return None if x is None else (("%d" % x) if float(x).is_integer() else ("%.2f" % x))


class _Об:
    """Об'єднання за спільним ключем (union-find)."""
    def __init__(self):
        self.б = {}

    def знайти(self, x):
        self.б.setdefault(x, x)
        while self.б[x] != x:
            self.б[x] = self.б[self.б[x]]
            x = self.б[x]
        return x

    def з_єднати(self, a, b):
        a, b = self.знайти(a), self.знайти(b)
        if a != b:
            self.б[max(a, b)] = min(a, b)


def перебрати(записи, знімки, ж, збагачення, виміри_кадрів, сьогодні):
    """Старі записи шести крамниць → записи варіантів. `знімки` — {домен: [товар Store API з `_варіації`]};
    `ж` — модуль `жниварка` (`варіанти_woo`, `факти_woo`, `woo_рецепт`).
    → (нові_записи, відповідність, збагачення, виміри_кадрів, звіт, черга): `черга` — варіанти з кадром, чий кадр
    ще не виміряний (перелік для ноутбука, рядок 5697). Вхідні словники не міняються."""
    нові_за_ід, відповідність, звіт, черга = {}, [], collections.OrderedDict(), []
    вилучені, результат_зб, результат_км = set(), dict(збагачення), dict(виміри_кадрів)
    наступний = останній_номер(записи)
    for домен in sorted(знімки):
        рецепт = ж.woo_рецепт(домен)
        старі = [з for з in записи if магазин(з) == домен]
        за_сторінкою = collections.defaultdict(list)       # сторінка → її старі записи: сторінки й варіантів
        for з in старі:
            за_сторінкою[норм_адреса(з["адреса"])].append(з)
        з_товару = {}                                       # id товару → (товар, старий запис, варіанти, факти)
        попередні_т = {}                                    # id товару → усі старі записи його сторінки
        лічба = звіт[домен] = collections.Counter(старих=len(старі))
        знайдені = {норм_адреса(т.get("permalink")) for т in знімки[домен]}
        лічба["немає_в_api"] = sum(1 for з in старі if норм_адреса(з["адреса"]) not in знайдені)
        # Товар знімка без записів на сторінці (усі його кольори вже вилучено як дублі минулим прогоном) лишається
        # членом класів: інакше повторний перезбір того самого знімка міняв би переможців класів (13315).
        без_записів = {}
        for т in знімки[домен]:
            попередні = за_сторінкою.get(норм_адреса(т.get("permalink")))
            база = "{0.scheme}://{0.netloc}".format(urlparse(т["permalink"]))
            варіанти = ж.варіанти_woo(т, база, рецепт)
            if варіанти is None:
                лічба["лишились_як_були"] += bool(попередні)      # атрибута кольору в товарі нема чи варіації не дісталися
                continue
            факти = ж.факти_woo(т, база, рецепт)
            assert len(факти) == len(варіанти)
            if not попередні:
                без_записів[т["id"]] = (т, None, варіанти, факти)
                continue
            д = next((з for з in попередні if слаг_адреси(з["адреса"], рецепт) is None), попередні[0])
            з_товару[т["id"]] = (т, д, варіанти, факти)
            попередні_т[т["id"]] = попередні
        # ── екземпляри (товар, варіант) і їхні класи за спільним кадром ───────────────────────────────
        екз, об, за_кадром = [], _Об(), {}
        for ід_т, (т, д, варіанти, факти) in sorted({**без_записів, **з_товару}.items()):
            багато = len(варіанти) > 1 or варіанти[0]["кольорів_у_товарі"] > 1
            for п, (в, ф) in enumerate(zip(варіанти, факти)):
                е = dict(ід_т=ід_т, п=п, т=т, д=д, в=в, ф=ф, багато=багато, ключ=len(екз))
                екз.append(е)
                об.знайти(е["ключ"])
                власні = в["кадри_джерело"] == "woo:variations"
                ключі = [ключ_кадру(к) for к in в["кадри"]] if власні else [ключ_кадру(в["кадри"][0])] if в["кадри"] else []
                for к in ключі:
                    if к in за_кадром:
                        об.з_єднати(за_кадром[к], е["ключ"])
                    else:
                        за_кадром[к] = е["ключ"]
        # Сторінки, що ділять кадр, — одна модель (фасон у кількох сторінках-кольорах).
        мод = _Об()
        for е in екз:
            мод.знайти(е["ід_т"])
        перші = {}
        for е in екз:
            перші.setdefault(об.знайти(е["ключ"]), е)
        for е in екз:
            мод.з_єднати(перші[об.знайти(е["ключ"])]["ід_т"], е["ід_т"])
        # Один колір фасону на двох сторінках = один варіант, навіть коли кадри варіацій на сторінках різні
        # (sunwin: «бежевий» сторінки 2221bg і «бежевий» сторінки 2221gy). Збігається слаг терма — код, не слово.
        за_слагом = {}
        for е in екз:
            if е["багато"]:
                к = (мод.знайти(е["ід_т"]), е["в"]["слаг"])
                if к in за_слагом:
                    об.з_єднати(за_слагом[к], е["ключ"])
                else:
                    за_слагом[к] = е["ключ"]
        класи = collections.defaultdict(list)
        for е in екз:
            класи[об.знайти(е["ключ"])].append(е)
        розміри_моделей = collections.Counter(мод.знайти(е["ід_т"]) for е in переможці_товарів(екз))
        лічба["найбільша_модель_товарів"] = max(розміри_моделей.values(), default=0)
        переможці = {}
        for кл, члени in класи.items():
            члени.sort(key=lambda е: (е["д"] is None, 0 if (е["багато"] and е["в"]["за_замовч"]) else 1,
                                      0 if е["д"] and _параметр(е["д"], "мова") == "укр" else 1, е["ід_т"], е["п"]))
            переможці[кл] = члени[0]
            лічба["дублів_вилучено"] += len(члени) - 1
            порядок = члени[:1] + sorted(члени[1:], key=lambda е: (е["ід_т"], е["п"]))   # сталий і для повторного перезбору
            власні = [к for x in порядок if x["в"]["кадри_джерело"] == "woo:variations" for к in x["в"]["кадри"]]
            if власні:
                члени[0]["кадри_класу"] = list(dict.fromkeys(власні))
        # ── ж-номери: старий — варіанту з кадром старої картки, решта кольорів — нові ───────────────
        виграли = collections.defaultdict(list)
        for е in sorted(екз, key=lambda е: (е["ід_т"], е["п"])):
            if переможці[об.знайти(е["ключ"])] is е:
                виграли[е["ід_т"]].append(е)
        ід_для, старий_для, сироти_ід = {}, {}, set()
        # Сторінка, якої вже нема в API, лишила ж-номер, чий перший кадр — кадр варіанта на іншій сторінці (sunwin:
        # колір живе на сестринській): номер переходить до цього варіанта, а не пропадає разом зі сторінкою.
        прийняті_адреси = {норм_адреса(д["адреса"]) for _, д, _, _ in з_товару.values()}
        осиротілі = {ключ_кадру(з["кадри"][0]): з["ід"] for з in старі
                     if з["кадри"] and норм_адреса(з["адреса"]) not in прийняті_адреси and з["ід"] not in {д["ід"] for _, д, _, _ in з_товару.values()}}
        for ід_т, (т, д, варіанти, факти) in sorted(з_товару.items()):
            вигр = виграли.get(ід_т) or []
            за_слагом_ст = {}
            for з in попередні_т[ід_т]:
                сл = слаг_адреси(з["адреса"], рецепт)
                if сл is not None:
                    за_слагом_ст.setdefault(сл, з)
            for е in вигр:                                   # запис з адресою варіанта — за його слагом
                з = за_слагом_ст.get(unquote(е["в"]["слаг"] or "").lower()) if е["багато"] else None
                if з is not None:
                    ід_для[id(е)], старий_для[id(е)] = з["ід"], з
            перший_кадр = ключ_кадру(д["кадри"][0]) if д["кадри"] else None
            вільні = [е for е in вигр if id(е) not in ід_для]
            власник = None
            if слаг_адреси(д["адреса"], рецепт) is None and д["ід"] not in ід_для.values():
                власник = next((е for е in вигр if перший_кадр and перший_кадр in {ключ_кадру(к) for к in (е.get("кадри_класу") or е["в"]["кадри"])}), None)
                if власник is None:                          # кадр сторінки не варіанта — номер іде вільному кольору
                    власник = next((е for е in вільні if е["багато"] and е["в"]["за_замовч"]), None) or next(iter(вільні), None)
                elif id(власник) in ід_для:                    # колір кадру вже має свій запис — сторінка стане дублем
                    власник = None
            if власник is not None:
                ід_для[id(власник)], старий_для[id(власник)] = д["ід"], д
            for е in вигр:
                if id(е) not in ід_для:
                    сирота = next((осиротілі.pop(к) for к in (ключ_кадру(x) for x in (е.get("кадри_класу") or е["в"]["кадри"])) if к in осиротілі), None)
                    if сирота:
                        ід_для[id(е)] = сирота
                        сироти_ід.add(сирота)
                        continue
                    наступний += 1
                    ід_для[id(е)] = "ж-%05d" % наступний
        # Старі записи сторінки без свого варіанта: запис сторінки, чий колір уже має запис варіанта, і колір, що
        # програв дубль іншій сторінці, — вилучаються, номер і вимір переходять до переможця класу; колір, якого в API
        # вже нема, лишається як був.
        зайняті, злиті = set(ід_для.values()), collections.defaultdict(list)
        for ід_т, (т, д, варіанти, факти) in sorted(з_товару.items()):
            свої = [е for е in екз if е["ід_т"] == ід_т]
            for з in попередні_т[ід_т]:
                if з["ід"] in зайняті:
                    continue
                сл = слаг_адреси(з["адреса"], рецепт)
                if сл is None:
                    перший = ключ_кадру(з["кадри"][0]) if з["кадри"] else None
                    е = next((е for е in свої if перший and перший in {ключ_кадру(к) for к in е["в"]["кадри"]}), свої[0])
                else:
                    е = next((е for е in свої if unquote(е["в"]["слаг"] or "").lower() == сл), None)
                if е is None:
                    лічба["колір_якого_нема_в_api"] += 1
                    continue
                ціль = переможці[об.знайти(е["ключ"])]
                вилучені.add(з["ід"])
                злиті[ід_для[id(ціль)]].append(з["ід"])
                зайняті.add(з["ід"])
                відповідність.append((домен, з["ід"], ід_для[id(ціль)], "вилучено: дубль (той самий колір на сторінці %s)" % ціль["ід_т"],
                                      ід_т, е["в"]["слаг"], мод.знайти(ід_т)))
                лічба["старих_ід_вилучено"] += 1
                результат_зб.pop(з["ід"] + "@" + домен, None)
                результат_км.pop(з["ід"] + "@" + домен, None)
        # ── записи ──────────────────────────────────────────────────────────────────────────────────────
        for стар in set(ід_для.values()) | {д["ід"] for _, д, _, _ in з_товару.values()}:
            результат_зб.pop(стар + "@" + домен, None)
            результат_км.pop(стар + "@" + домен, None)
        for ід_т, (т, д, варіанти, факти) in sorted(з_товару.items()):
            for е in виграли.get(ід_т) or []:
                ід = ід_для[id(е)]
                сирота = ід in сироти_ід
                давній = старий_для.get(id(е), д)
                зап = _запис(давній, т, е, ід, str(мод.знайти(ід_т)), сьогодні, багато=е["багато"], ж=ж, рецепт=рецепт)
                нові_за_ід[ід] = зап
                лічба["записів_варіантів"] += 1
                лічба["нових_ід"] += id(е) not in старий_для and not сирота
                лічба["ід_сторінки_якої_нема_перейшов_до_кольору"] += сирота
                лічба["варіантів_без_кадру"] += not зап["кадри"]
                спосіб = ("ід сторінки, якої нема в API, — колір на іншій сторінці" if сирота
                          else "лишено ід" if id(е) in старий_для else "новий ід (колір моделі)")
                стар_ід = ід if сирота else давній["ід"]
                відповідність.append((домен, стар_ід, ід, спосіб, ід_т, е["в"]["слаг"], мод.знайти(ід_т)))
                _вимір(збагачення, виміри_кадрів, результат_зб, результат_км, [стар_ід] + злиті.get(ід, []) + [д["ід"]], ід, зап,
                       лічба, черга)
    # ── складання: старі записи на своїх місцях, нові — наприкінці ──────────────────────────────────
    результат = []
    for з in записи:
        if з["ід"] in вилучені:
            continue
        результат.append(нові_за_ід.pop(з["ід"], з))
    результат.extend(нові_за_ід[ід] for ід in sorted(нові_за_ід))
    return результат, відповідність, результат_зб, результат_км, звіт, черга


def _вимір(збагачення, виміри_кадрів, результат_зб, результат_км, стар_ід, ід, зап, лічба, черга):
    """Вимір, зроблений з кадру цього варіанта (та сама адреса), лишається; інакше запису збагачення нема. `стар_ід` —
    старий ід чи список їх за пріоритетом (запис варіанта, злиті дублі, запис сторінки): береться перший вимір із кадру
    варіанта."""
    домен = магазин(зап)
    кадри = {ключ_кадру(к) for к in зап["кадри"]}
    старі = list(dict.fromkeys([стар_ід] if isinstance(стар_ід, str) else стар_ід))
    зб = next((з for з in (збагачення.get(с + "@" + домен) for с in старі) if з and ключ_кадру(з.get("фото")) in кадри), None)
    if зб:
        результат_зб[ід + "@" + домен] = зб
        лічба["вимір_кольору_лишився"] += 1
    else:
        if зап["кадри"]:
            лічба["кадр_без_виміру"] += 1
            черга.append((ід, домен, _параметр(зап, "id_магазину"), зап["кадри"][0]))
    км = next((к for к in ([в for в in (виміри_кадрів.get(с + "@" + домен) or []) if ключ_кадру(в.get("url")) in кадри]
                              for с in старі) if к), [])
    if км:
        результат_км[ід + "@" + домен] = км


def _запис(д, т, е, ід, ключ_моделі, сьогодні, багато, ж, рецепт):
    """Запис варіанта: службові поля старого запису `д`, колір/кадри/розміри/наявність — адаптера."""
    в, ф = е["в"], е["ф"]
    адреса = т["permalink"]                                  # як дала платформа (зі слешем): це адреса, за якою купують
    if багато and в["слаг"]:
        адреса += "?attribute_%s=%s" % (рецепт["колір"], в["слаг"])
    параметри = [["id_магазину", str(т["id"]), "с"], ["канал", КАНАЛ, "с"], ["адаптер", "woo v1", "с"],
                 ["наявність", "є" if в["є"] else "нема", "с"], ["Колір", в["слово"], "с"],
                 ["колір_джерело", "woo:variations" if багато else "woo:attributes", "с"],
                 ["кадри_джерело", ("woo:variations" if е.get("кадри_класу") else в["кадри_джерело"]) or "невідомі", "с"]]
    власник = ж.власник_варіанта_woo(т, в, адреса, рецепт)     # кадри сестер класу (`кадри_класу`) доказу не мають
    if власник is not None:
        параметри.append(["власник_кадру", власник, "с"])
    if в["розміри"]:
        параметри.append(["розміри", ", ".join(в["розміри"]), "с"])
        if в["розміри_в_наявності"]:
            параметри.append(["розміри_в_наявності", ", ".join(в["розміри_в_наявності"]), "с"])
        параметри.append(["розміри_джерело", в["розміри_джерело"], "с"])
    for ім, знач, рід in д["параметри"]:
        if ім in ПЕРЕПИСАНІ:
            continue
        assert рід == "с" or ім.startswith("~"), (д["ід"], ім)
        параметри.append([ім, знач, рід])
    параметри.append(["знято", сьогодні, "с"])
    зап = {"схема": д["схема"], "ід": ід, "доступність": "true" if в["є"] else "false", "назва": д["назва"]}
    for поле in ("виробник",):
        if поле in д:
            зап[поле] = д[поле]
    зап["артикул"] = ключ_моделі
    ціна = ф.get("ціна")
    зап["ціна"] = _ціна(ціна) if ціна is not None else д.get("ціна")
    if ф.get("ціна_стара") and ціна is not None and ф["ціна_стара"] > ціна:
        зап["стара_ціна"] = _ціна(ф["ціна_стара"])
    зап["валюта"], зап["категорія"], зап["адреса"] = д["валюта"], д["категорія"], адреса
    зап["збирач"], зап["кадри"], зап["опис"] = ЗБИРАЧ, list(е.get("кадри_класу") or ф["фото"]), д["опис"]
    зап["параметри"], зап["вихід"] = параметри, dict(д["вихід"])
    return зап


def писати_відповідність(рядки, шлях=ВІДПОВІДНІСТЬ):
    with io.open(шлях, "w", encoding="utf-8", newline="\n") as f:
        f.write("магазин\tстарий_ід\tновий_ід\tспосіб\tid_товару_woo\tслаг_кольору\tмодель_woo\n")
        for р in sorted(рядки, key=lambda р: (р[0], р[1], р[2] or "")):
            f.write("\t".join("" if x is None else str(x) for x in р) + "\n")


def писати_чергу(рядки, шлях=ЧЕРГА):
    with io.open(шлях, "w", encoding="utf-8", newline="\n") as f:
        f.write("ід\tмагазин\tid_товару_woo\tперший_кадр\n")
        for р in sorted(рядки):
            f.write("\t".join(р) + "\n")


def читати_json_gz(шлях):
    with gzip.open(шлях, "rb") as f:
        return json.loads(f.read().decode("utf-8"))


def писати_json_gz(дані, шлях, **kw):
    with gzip.GzipFile(шлях, "wb", compresslevel=9, mtime=0) as f:
        f.write(json.dumps(дані, ensure_ascii=False, **kw).encode("utf-8"))


def читати_знімки(тека):
    """{домен: [товар]} із `<тека>/<домен>.json.gz` (пише `woo_знімок.py`)."""
    вих = {}
    for ім in sorted(os.listdir(тека)):
        if ім.endswith(".json.gz") and not ім.endswith(".список.json.gz"):
            вих[ім[:-len(".json.gz")]] = читати_json_gz(os.path.join(тека, ім))
    return вих
