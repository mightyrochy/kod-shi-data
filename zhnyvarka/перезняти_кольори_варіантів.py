# -*- coding: utf-8 -*-
"""СПИСОК КОЛЬОРІВ ТОВАРУ ЗІ СТОРІНКИ КРАМНИЦІ — у `~Колір` наявного каталогу. Рядок 142 дошки, 23.09.2026.

ЗАПУСК
  python3 перезняти_кольори_варіантів.py --каталог ../каталог_повний.xml.gz --магазин sarahberlin.com \
          --знімки /tmp/sb --звіт /tmp/sb.json            # лише зняти й порахувати
  python3 перезняти_кольори_варіантів.py ... --записати   # + дописати <param name="~Колір"> у каталог

НАЩО. `фід_варіант` (джерела) вибирає слово крамниці для запису-ТОВАРУ з кількома
кольорами зі списку `~Колір`: фото картки показує один із варіантів, і назвою має бути
слово крамниці саме для нього. У sarahberlin такого списку в каталозі нема, а поле
«Колір» — ПЕРШИЙ колір із вибору на сторінці: ж-00559 «Сукня з натурального шовку…» —
поле «пудровий», на сторінці вибір «пудровий, синій, червоний», в описі «Колір:
червоний», галерея червона. Код казав «пудровий» під червоною сукнею.

ЩО РОБИТЬ. Для кожного офера крамниці тягне картку (кеш і перевірка кінцевої адреси —
`перезняти_галереї.зняти`), бере підписи перемикача кольору (`pv_opt[…]` зі свотчем
`variant-opt-body--circle`) у порядку сторінки і, з `--записати`, дописує їх одним
`<param name="~Колір">` перед `</offer>` — лише там, де такого параметра ще нема.
Решта байтів каталогу не рухається (той самий прийом, що `переписати_picture`); id,
фото, поле «Колір» — без змін. Сторінка не відкрилась, зникла або перемикача кольору
не має — офер не чіпається, а звіт називає причину.
"""
import argparse, concurrent.futures, html, json, os, re, sys
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import перезняти_галереї as пг                                               # noqa: E402

_ПЕРЕМИКАЧ = re.compile(r'<input[^>]*name="pv_opt\[(\d+)\]"[^>]*data-value-label="([^"]*)"[^>]*/?>\s*'
                        r'<span class="([^"]*)"')


def кольори_сторінки(тіло):
    """Підписи перемикача кольору (група зі свотчами-кружечками) у порядку сторінки."""
    вих = []
    for м in _ПЕРЕМИКАЧ.finditer(тіло or ""):
        if "variant-opt-body--circle" in м.group(3):
            с = html.unescape(м.group(2)).strip()
            if с and с not in вих:
                вих.append(с)
    return вих


def одна(запис, тека):
    """Один офер → рядок звіту: кольори зі сторінки або причина, чому їх нема."""
    ід, url, _ = запис
    код, тіло, кінцевий = пг.зняти(url, тека)
    р = dict(ід=ід, url=url, код=код, кольори=[], причина=None)
    if код != 200 or not тіло or len(тіло) < 2000:
        р["причина"] = "картка не відкрилась (код %s, %d Б)" % (код, len(тіло or ""))
    elif пг._шлях_адреси(кінцевий) != пг._шлях_адреси(url):
        р["причина"] = "річ зникла з крамниці: редирект на %s" % кінцевий
    else:
        р["кольори"] = кольори_сторінки(тіло)
        if not р["кольори"]:
            р["причина"] = "на сторінці нема перемикача кольору"
    return р


_ОФЕР = re.compile(r"<offer\b[^>]*\bid=\"([^\"]+)\"[^>]*>(.*?)</offer>", re.S)


def дописати_список(текст, нове, магазин):
    """`<param name="~Колір">` перед `</offer>` названих оферів без такого параметра; решта байтів як була."""
    n = [0]

    def офер(м):
        ід, тіло = м.group(1), м.group(2)
        кольори = нове.get(ід)
        if not кольори or ("<param name=\"магазин\">%s</param>" % магазин) not in тіло \
                or re.search(r'<param name="~(?:Колір|колір|color|Color|цвет)">', тіло):
            return м.group(0)
        n[0] += 1
        return м.group(0)[:-len("</offer>")] + "<param name=\"~Колір\">%s</param></offer>" % \
            html.escape(", ".join(кольори), quote=False)

    return _ОФЕР.sub(офер, текст), n[0]


def main(argv=None):
    """Розбір аргументів, прогін, звіт; `--записати` дописує `~Колір` у каталог."""
    ап = argparse.ArgumentParser()
    ап.add_argument("--каталог", required=True)
    ап.add_argument("--магазин", required=True)
    ап.add_argument("--знімки", default="")
    ап.add_argument("--звіт", default="")
    ап.add_argument("--потоків", type=int, default=4)
    ап.add_argument("--записати", action="store_true")
    а = ап.parse_args(argv)
    if а.знімки:
        os.makedirs(а.знімки, exist_ok=True)
    сирі = пг.байти(а.каталог)
    записи = пг.офери_крамниці(ET.fromstring(сирі), а.магазин)
    with concurrent.futures.ThreadPoolExecutor(а.потоків) as ex:
        звіт = list(ex.map(lambda з: одна(з, а.знімки), записи))
    з_кольорами = [р for р in звіт if р["кольори"]]
    print("оферів %d · зі списком кольорів %d · без: %s" % (
        len(звіт), len(з_кольорами),
        json.dumps({п: sum(1 for р in звіт if р["причина"] == п) for п in {р["причина"] for р in звіт if р["причина"]}},
                   ensure_ascii=False)), flush=True)
    if а.звіт:
        json.dump(звіт, open(а.звіт, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    if а.записати:
        текст, n = дописати_список(сирі.decode("utf-8"), {р["ід"]: р["кольори"] for р in з_кольорами}, а.магазин)
        пг.записати(текст.encode("utf-8"), а.каталог)
        print("у каталозі дописано ~Колір у %d оферів" % n, flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
