# З Р2-2а (01.10.2026) сіль не діяла: рука 2 брала той самий пул і порядок, що й рука 1, — і та сама
# сукня стояла в 22 % пар із сукнею (рядок 5215). СІД-РУКИ-2 (рядок 5505, власник 15.10.2026) сіль
# повертає: ті самі кандидати (розводу пулу нема), свій порядок рівних і семплер.
СІЛЬ_РУКИ_2 = 23      # 7, 11 і 13 уже зайняті псуванням, жеребом поломки і гілкою


def _сід_руки(сід, рука2=False):
    """Сід, яким РУКА впорядковує рівне у слоті: рука 2 — сід прогону + `СІЛЬ_РУКИ_2` (рядок 5505).

    Стоїть в одному місці, бо його читають двоє: `_входи_пакета` (а через нього
    ключ кеша) і сам пакет (`сцен["сід"]` → `composer._перемішати`, семплер,
    `composer.добір_слота`). Два обчислення цього числа розійшлись би на першій же
    правці, і суд руки 2 пішов би не тим пулом, яким складали.
    """
    # СВІЙ СІД НА ТИХ САМИХ КАНДИДАТАХ (рядок 5505, скасовує частину Р2-2а): кандидати й бюджет
    # ті самі, що в руки 1 (пул руки 1 з добору руки 2 не виключається), а порядок рівних і
    # семплер — свої, тож картки рук 1 і 2 не складаються з тієї самої голови слота. Сід 0
    # лишається 0 (див. вище). Читають ключ кеша, пакет і уважний вибір — тим самим числом.
    return int(сід or 0) + (СІЛЬ_РУКИ_2 if рука2 and сід else 0)


