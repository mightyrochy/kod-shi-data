def _рука2(d, гілка, F, T, п, зріст, kw, якір, намір, схема_вибір=None, діє=None):
    """ОДИН жереб руки 2 для `запити` і `від_моделі`: які ПРАВИЛА вимкнено (Р2-2а; кілька — рядок 5503).

    Повертає (поломки, F_д, T_д, пд, гд, сц2, текст2, псування, доступні, поломка, пасп2) —
    та сама форма, що доти, щоб викликачі не мінялись: людина, сценарій, текст випадку
    й паспорт — ТІ САМІ, що в руки 1 (поломок входу більше нема); `поломки` = {"rule_off"};
    `поломка` — {назва, правило, тема, коди, місця, ключі_брифа, що_змінено, доступні,
    без_входу, правила, поломок, аспекти} для виходу `запити`, журналу вердикту й звіту власника;
    `правило` і `тема` — ID і теми через «+», `правила` — ID по одному, `поломок` — скільки.

    ПАКЕТ ПАЛІТРИ ПЕРЕРАХОВУЄТЬСЯ БЕЗ ПРАВИЛА, коли правило діє в пулі палітри (ранг основ,
    вікна біля обличчя, рядок металу): `_пакет` під контекстом `вимкнено` — ті самі
    аргументи, що в `_пакет_гілки`. Інакше «вимкнене в пулі» лишилось би на словах."""
    import правило_руки2 as _ПР2
    # `діє` — де правила переліку діють на цьому прогоні (`міст_запити._дія_правил`, Р2-2б):
    # жереб бере спершу те, що діє в пулі, і чесно каже `пара`, коли не діє жодне
    запис, дост, без_входу, пара = _ПР2.жереб(d, п, діє=діє)
    пд = п
    if "pool" in запис["місця"]:
        with _ПР2.зламано(запис["коди"]):
            пд = _пакет(F, T, зріст, kw, якір, намір, _самозвіт(d), d.get("вибір_кольору"),
                        d.get("драп"), явні=((схема_вибір,) if схема_вибір else ()))
    # ІМ'Я СИЛЬНІШЕ ЗА НОМЕР: без правила ранг основ може переставити гілки розвилки
    гд = _індекс_гілки(пд["палітри"]["розвилка"], гілка, схема_вибір) if пд.get("готово") else гілка
    поломка = dict(
        назва="правило", правило=запис["ід"], тема=запис["тема"], коди=list(запис["коди"]),
        місця=list(запис["місця"]), ключі_брифа=list(запис["бриф"]),
        # СКІЛЬКИ Й ЯКІ ПРАВИЛА (рядок 5503) і їхні аспекти картки (рядок 5502) — для розбору скарг
        правила=list(запис["правила"]), поломок=запис["поломок"], аспекти=list(запис["аспект"]),
        що_змінено=_що_змінено(запис, дост, пара, діє), деталі={}, доступні=дост,
        # ЯКИЙ ЯРУС ЖЕРЕБУ (Р2-2б, рядок 435): pool — правило діє в пулі руки 1;
        # prompt_only — лише в її промпті; judge — лише в суді (Р2-2г); empty — не діє жодне з входом, пара порожня
        пара=пара, діє=(діє or None),
        # ЧОГО ЖЕРЕБ НЕ МІГ УЗЯТИ ЦЬОГО ПРОГОНУ, і чому — полем, а не мовчанням (п.4)
        без_входу=без_входу,
        вхід=(запис["ід"] not in (без_входу or {})),
        нагода_у_тексті=None, псування_сценарію="")
    # ВМ-3а (рядок 224): ім'я поломки — код (`hand_2_broken=rule_off` у діагнозі), не слово
    return ({"rule_off"}, F, T, пд, гд, d.get("сценарій") or {}, d.get("випадок") or "", "",
            дост, поломка, d.get("паспорт"))


