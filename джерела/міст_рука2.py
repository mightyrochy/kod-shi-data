def _сід_руки(сід, рука2=False):
    """Сід, яким РУКА впорядковує рівне у слоті: з Р2-2а — сирий сід прогону обом рукам.

    Стоїть в одному місці, бо його читають двоє: `_входи_пакета` (а через нього
    ключ кеша) і сам пакет (`сцен["сід"]` → `composer._перемішати`, семплер,
    `composer.добір_слота`). Два обчислення цього числа розійшлись би на першій же
    правці, і суд руки 2 пішов би не тим пулом, яким складали.
    """
    # СПІЛЬНИЙ ПУЛ І ВИПАДОК (Р2-2а, 01.10.2026): рука 2 = рука 1 без правила на ТОМУ
    # САМОМУ пулі, тож порядок рівних у неї той самий — сіль більше не додається.
    # Доти сіль розводила голови слотів двох рук (вимір біля `СІЛЬ_РУКИ_2`), і вердикт
    # пари міряв ще й те, яка рука витягла кращі речі. Сигнатура лишається: її читають
    # ключ кеша, пакет і уважний вибір.
    return int(сід or 0)


