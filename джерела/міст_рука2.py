def _підмінити_нагоду(текст, стара, нова, сегментами=True):
    """Нагода руки 2 в ТЕКСТІ випадку, а не лише в даних (Т-11 крок 2).

    ЩО ЦЕ ЛІКУЄ. Поломка «доречність» міняла ключ `сценарій.нагода`, а рядок
    випадку — той самий, що їде в `ПАКЕТ_V1.випадок.рядок` і в руки 3–4, — лишався
    цілим, коли ключа в ньому не було дослівно. На стендовому вході це рівно так:
    нагода «робота», а рядок каже «робочий день, офіс, 09:00, 18 °C» (виміряно
    V25: «у тексті випадку слова нагоди нема — не підмінено»). Модель діставала
    ТОЙ САМИЙ опис події, що й рука 1, і поломка існувала лише в даних коду.

    Три спроби, від точної до грубої: ключ нагоди, її підпис із довідника
    (`Робота`, `Траур` — те, з чого показ будує перший сегмент рядка), і, коли
    жодного нема, ПЕРШИЙ СЕГМЕНТ рядка: за побудовою `показ.випадокРядком` це і є
    нагода. Повертає (текст, чим_підмінено) — `None` у другому означає, що текст
    не змінився, і це йде в опис псування, а не в тишу.

    `сегментами=False` лишає лише перші дві спроби, і це не дрібниця: рядок
    випадку код СКЛАДАЄ з сегментів, а `паспорт.подія` — це СЛОВА ЖІНКИ. Замінити
    її речення цілком одним словом «Траур» означало б не зсунути нагоду, а стерти
    те, що вона сказала, — і рука 2 відповідала б на інше питання, а не гірше на те саме.
    """
    import pipeline as _PL
    т = str(текст or "")
    підпис = lambda к: _PL.ДОВІДНИК_ПІДПИСИ["нагоди"].get(к, (str(к).replace("_", " "), ""))[0]
    нове = підпис(нова)
    for кандидат in (str(стара), підпис(стара), str(стара).replace("_", " ")):
        якщо = str(кандидат or "").strip()
        if not якщо:
            continue
        т2, n = _re_сц.subn(r"(?i)\b%s\b" % _re_сц.escape(якщо), нове, т, count=1)
        if n:
            return т2, "слово «%s» → «%s»" % (якщо, нове)
    if not сегментами:
        return т, None
    # НАГОДИ В ТЕКСТІ НЕМА ЖОДНИМ СЛОВОМ — міняємо перший сегмент. Рядок випадку
    # склеєний з чотирьох частин (нагода · місце · година · температура), і
    # дописати п'яту означало б дати моделі ДВІ події замість однієї зміщеної.
    м = _re_сц.search(r"\s*(?:·|,|;)\s*", т)
    if м:
        return нове + т[м.start():], "перший сегмент рядка → «%s»" % нове
    return (нове, "рядок випадку → «%s»" % нове) if т.strip() else (т, None)


def _зіпсувати_сценарій(с, текст, сід=0, поломки=None):
    """Рука 2: сценарій ТРОХИ не той. Поломок три — температура, година, доречність.
    З живого шляху сюди приходить РІВНО ОДНА (`_поломки` через `_рука2`); набір із
    кількох лишається можливим лише для викликача, який подасть його сам.
    Величини теж випадкові, у діапазоні відсотків шкали, а не фіксований крок:
      · температура: ±15–40 % шкали 25 °C (≈ 4–10 °C), знак випадковий;
      · година: ±10–25 % доби (≈ 2–6 год), знак випадковий;
      · доречність: нагода на 1–2 щаблі ошатності вбік (за таблицею місць корпусу) —
        не кардинально інша подія, а трохи недоречна.
    Повертає (dict, текст, опис, деталі). Число, якого в тексті випадку нема, не
    підміняється — і це названо в описі. НАГОДА — інакше: вона підміняється завжди
    (`_підмінити_нагоду`), бо без неї поломка «доречність» не доїжджає до моделі
    зовсім. `деталі` каже, чим саме, і йде в поле `поломка` виходу `запити`."""
    import random as _r, outfit as _O
    import реєстр_правил as _РЕЄСТР, формальність as _ФОРМ   # Н-02-01, сесія 4
    rnd = _r.Random(int(сід or 0) + 7)
    # Набір може прийти ззовні (єдиний жереб на всі поломки руки 2). Без нього —
    # старий локальний жереб лише по сценарію: так CLI й гейти лишаються робочими.
    if поломки is None:
        поломки = [п for п in ("температура", "година", "доречність") if rnd.random() < 0.5]
        if not поломки:
            поломки = [rnd.choice(("температура", "година", "доречність"))]
    с2 = dict(с or {}); опис = []; т2 = str(текст or ""); деталі = {}
    if "температура" in поломки and с2.get("темп_c") not in (None, ""):
        частка = rnd.uniform(0.15, 0.40) * rnd.choice((-1, 1))
        зсув = round(частка * 25.0, 1)
        с2["темп_c"] = round(float(с2["темп_c"]) + зсув, 1); опис.append("температура %+.1f °C (%+.0f %% шкали 25 °C)" % (зсув, частка * 100))
        деталі["температура"] = "%+.1f °C" % зсув
        т2, n = _re_сц.subn(r"(-?\d+(?:[.,]\d+)?)\s*°\s*C", "%.0f °C" % с2["темп_c"], т2, count=1)
        if not n: опис.append("у тексті випадку температури нема — не підмінено")
    if "година" in поломки and с2.get("година") not in (None, ""):
        частка = rnd.uniform(0.10, 0.25) * rnd.choice((-1, 1))
        зсув = int(round(частка * 24))
        с2["година"] = int((int(с2["година"]) + зсув) % 24); опис.append("година %+d (%+.0f %% доби)" % (зсув, частка * 100))
        деталі["година"] = "%+d год" % зсув
        т2, n = _re_сц.subn(r"\b(\d{1,2}):(\d{2})\b", "%02d:\\2" % с2["година"], т2, count=1)
        if not n: опис.append("у тексті випадку години нема — не підмінено")
    if "доречність" in поломки and с2.get("нагода"):
        _н = с2["нагода"]; _м = _ФОРМ.НАГОДА_У_МІСЦЕ.get(_н)
        if _м in _ФОРМ.МІСЦЯ_ДІАПАЗОНИ:
            центр = lambda k: sum(_ФОРМ.МІСЦЯ_ДІАПАЗОНИ[k]) / 2.0
            сусіди = [н for н, м in _ФОРМ.НАГОДА_У_МІСЦЕ.items()
                      if н != _н and м in _ФОРМ.МІСЦЯ_ДІАПАЗОНИ and 1.0 <= abs(центр(м) - центр(_м)) <= 2.0]
            if сусіди:
                нова = rnd.choice(sorted(сусіди))
                с2["нагода"] = нова; с2["місце"] = None      # місце береться з нової нагоди
                опис.append("нагода %s → %s (ошатність %.1f → %.1f)" % (_н, нова, центр(_м), центр(_ФОРМ.НАГОДА_У_МІСЦЕ[нова])))
                т2, чим = _підмінити_нагоду(т2, _н, нова)
                опис.append("у тексті випадку: " + (чим or "міняти нічого — рядок порожній"))
                деталі["доречність"] = "%s → %s" % (_н, нова)
                деталі["нагода_у_тексті"] = bool(чим)
                деталі["нова_нагода"] = нова
            else:
                опис.append("доречність: сусідньої нагоди в таблиці нема — не зламано")
    return с2, т2, "; ".join(опис), деталі


