def без_входу(речі=None):
    """Правила теми-11, що входу не мають. Виходять ПИТАННЯМИ з названим блокером:
    мовчазний прохід заборонено, «без входу» ≠ «пройдено».

    `речі` ЧИТАЮТЬСЯ (доти параметр стояв у сигнатурі й не вживався —
    `аудит/КЛАС_МЕРТВІ_ПАРАМЕТРИ.md`, рядок «outer.без_входу(речі)»). Запис із
    полем `коли` — предикат над ВЕРХНІМ ШАРОМ цього образу: черга на вхід
    зникає, щойно вхід приходить. Записи без `коли` сталі, бо їхньої величини
    (CLO, лофт) не дасть жодне поле фіду.
    """
    зн = []
    в = _верхній(речі or [])
    for прав, сп in БЕЗ_ВХОДУ.items():
        коли = сп.get("коли")
        if коли is not None and not коли(в or {}):
            continue
        з = dict(_зн(прав, "питання",
            "%s — входу нема" % сп["що"], ["образ"],
            "%s. Наслідок: %s" % (сп["блокер"], сп["наслідок"]),
            ремонт="що це оживить: %s" % сп["оживить"],
            ламається="правило записане в корпусі й не виконується — це ЧЕРГА, "
                      "названа вголос, а не провал і не виправдання"
                      + ("; " + сп["примітка"] if сп.get("примітка") else "")),
            сила_нп=0.0, сила_нп_джерело="входу нема: %s" % сп["блокер"][:60])
        з["навіщо"] = сп["оживить"]
        зн.append(з)
        _СЛ.запис(прав, "без входу", "без_входу", значення=сп["блокер"][:50],
                  сила=0.0, напрям="черга, не провал")
