def шари(запис=None):
    """Імена файлів, оголошені в полі `шар` — одного запису або всіх одразу.

    Поле — рядок «a.py, b.py» через кому; «—» означає «шару нема» і файлом не є.
    """
    записи = [запис] if запис is not None else list(СІМʼЇ.values()) + list(ВИНЯТКИ.values())
    out = set()
    for з in записи:
        for x in (з.get("шар") or "—").split(","):
            x = x.strip()
            if x and x != "—":
                out.add(x)
    return out


def фантомні_шари(тека=None):
    """Імена з поля `шар`, яких у теці джерел НЕМА. Має бути порожньо.

    ЧОМУ ЦЕ ФУНКЦІЯ ПРИЛАДУ, А НЕ ОКО (наряд Н-V21-043). `шар` — єдине поле
    цього реєстру, яке називає щось поза ним самим, і єдине, яке ніхто не
    звіряв: перейменування кириличних модулів на латиницю (`бриф.py` →
    `brief.py` і ще сім) лишило тут вісім імен неіснуючих файлів, і вони
    прожили місяці в `ПРАВИЛА.md` та `ЗВЕДЕННЯ.md` як «оголошене місце».
    Помилка, яку ніщо не коштує, не виправляється; тому лічбу робить прогін.
    """
    тека = тека or os.path.dirname(os.path.abspath(__file__)) or "."
    return sorted(ф for ф in шари() if not os.path.exists(os.path.join(тека, ф)))


def знаменник(корпус):
    """Чесний знаменник гейта: правила, які МАЮТЬ бути виконуваними ЗАРАЗ.
    Заблоковані — окрема черга, не провал; «ні» — не рахується взагалі."""
    так, блок, ні, невідомі = set(), {}, set(), set()
    for ід in корпус:
        р = рід(ід)
        в = р["виконуваний"]
        if в == "так":
            так.add(ід)
        elif в == "заблоковано":
            блок.setdefault(р.get("блокер", "не названо"), set()).add(ід)
        elif в == "?":
            невідомі.add(ід)
        else:
            ні.add(ід)
    return dict(так=так, заблоковані=блок, ні=ні, невідомі=невідомі)


