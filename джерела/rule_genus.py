def _сімʼя(ід):
    # ЧЕРЕЗ `ід_правил`, А НЕ `rsplit` (10.09.2026). Голий `rsplit` по останньому
    # дефісу на суфіксному ID (`K-COL-04-M`) давав сімʼю «K-COL-04», якої не
    # існує, — запис у СІМʼЇ не знаходився, і варіант правила мовчки лишався з
    # родом «?», тобто падав у відро некласифікованих замість свого.
    return ІП.сімʼя(ід) or ід.rsplit("-", 1)[0]


def рід(ід):
    """→ dict(рід, виконуваний, шар, чому[, блокер]). Невідома сімʼя не
    вигадується: повертається рід «?», і гейт рахує його окремо."""
