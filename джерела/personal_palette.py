РАНГ_РИС = {"очі": 1, "волосся": 2, "шкіра": 3, "макіяж": 4}   # R-COL-17 · T2 порядок (Perrett 2023); макіяж — обрана, завжди останній
РОЛЬ_РИС = {"очі": "акцент", "волосся": "нейтраль", "шкіра": "світла_нейтраль", "макіяж": "обрана"}   # K-ECHO-01 · T3 (Zyla, Flusser, Lamport)
ВІДНОШЕННЯ = ("analogous", "complementary", "split")   # з cs.RELATIONS; tonal/triadic — режими схеми, не палітри
_ХРОМА_ВНИЗ, _ХРОМА_ВГОРУ = 0.28, 0.32   # ті самі T3-константи, що в cs.feature_spectrum — одне джерело, не копія
_ПОДУШКА_C_АХРОМ = 2.0                    # ахроматична риса не звужує хрому до нуля: rel_C 0 → нижня межа 0
_ШИРИНА_REL_C = 0.08                      # T3 · ширина згладжування смуги хроми (cs.WIDTHS дає таку ж для L, C, h);
                                          # був голий літерал у лямбді — ззовні не читався

def членство(смуга, x):
    """Сила членства значення в смузі людини: 0..1, неперервно (cs.soft), не гейт.

    ЧОМУ ЦЕ ФУНКЦІЯ МОДУЛЯ, А НЕ ЛЯМБДА В СМУЗІ (P29, 11.09.2026). Смуги віддавали
    `членство` замиканням. Наслідків було два, і обидва — не про стиль:
      · палітра людини НЕ СЕРІАЛІЗУВАЛАСЬ: `json.dumps(палітра(F))` кидав
        TypeError, тобто зону в LCh не можна було ні закешувати, ні покласти в
        журнал, ні віддати мостом — єдиний спосіб винести її з процесу не існував;
      · ширина згладжування була ЗАМКНЕНА в лямбді: прочитати, якою вона була,
        ззовні не міг ніхто, тож перевірити смугу можна було лише повторивши код.
    Тепер смуга — це ДАНІ (`межі`, `ширина`), а рахує їх одна функція. `None`
    замість смуги дає 1.0: нема смуги — нема й зниження, і читач не мусить
    розгалужуватись на кожному виклику.
    """
    if not смуга: return 1.0
    lo, hi = смуга["межі"]
    return round(cs.soft(float(x or 0.0), lo, hi, смуга["ширина"]), 3)

def рід_риси(nm):
    if nm.startswith(cs.ПРЕФІКС_МАКІЯЖУ): return "макіяж"
    for k in ("очі", "волосся", "шкіра"):
        if nm.startswith(k): return k
    return None

def _дані(F):
    """Дані риси (шкіра/волосся/очі з під-рисами), без макіяжу й службових ключів."""
    return {nm: f for nm, f in F.items()
            if not nm.startswith("_") and рід_риси(nm) in ("очі", "волосся", "шкіра") and isinstance(f, dict)}

def _обрані(F):
    return {nm: f for nm, f in F.items() if рід_риси(nm) == "макіяж" and isinstance(f, dict)}

def смуга_світлоти(F):
    """K-ECHO-01 / K-CON-01: «її чорний» і «її білий» — найтемніша і найсвітліша ДАНА риса
    (у складного ока — кільце райдужки, F["очі_кільце"], Zyla); смуга ± крок K-COL-01.
    Сила членства — неперервна (cs.soft), не гейт; рахує її `членство(смуга, L)`."""
    д = _дані(F)
    if not д: return None
    # ГРАДІЄНТ (омбре) не дає мод: density() віддає ОДНУ середню моду L*≈36, якої нема в
    # жодному пасмі, але зберігає РОЗКИД (q90−q10) у F["_розподіли"]. Для смуги
    # беруться краї розкиду, не середина: «її чорний» — темний край омбре, а не середнє.
    # Виміряно 24.08.2026: плавний градієнт 200 зразків → мода 36, розкид 38.6.
    розп = (F.get("_розподіли") or {})
    def _краї(nm, f):
        рід = рід_риси(nm); r = (розп.get(рід) or {}).get("розкид") or 0.0
        n_мод = len((розп.get(рід) or {}).get("моди") or []) if isinstance((розп.get(рід) or {}).get("моди"), list) else (розп.get(рід) or {}).get("моди") or 1
        # розкид розтягує лише ОДНОмодову рису: у багатомодової краї вже є окремими під-рисами
        return (f["L"] - r/2, f["L"] + r/2) if (r and n_мод == 1) else (f["L"], f["L"])
    краї = {nm: _краї(nm, f) for nm, f in д.items()}
    темна = min(д.items(), key=lambda kv: краї[kv[0]][0])
    світла = max(д.items(), key=lambda kv: краї[kv[0]][1])
    крок = O.C["step_min"]
    lo, hi = max(0.0, краї[темна[0]][0] - крок), min(100.0, краї[світла[0]][1] + крок)
    return dict(її_чорний=dict(риса=темна[0], L=round(краї[темна[0]][0], 1), hex=темна[1].get("hex")),
                її_білий=dict(риса=світла[0], L=round(краї[світла[0]][1], 1), hex=світла[1].get("hex")),
                вісь="L", межі=(round(lo, 1), round(hi, 1)), ширина=cs.WIDTHS["L"],
                джерело="Zyla: «свій чорний» — кільце райдужки/найтемніше волосся, «свій білий» — шкіра; "
                        "крок K-COL-01 (T3) як подушка; поза смугою — не заборона, а спадна сила",
                сила="hint")

def смуга_хроми(F):
    """Ясність людини як вікно rel_C від даних рис (feature_spectrum-константи, T3)."""
    д = _дані(F)
    rel = [f.get("rel_C", 0.0) or 0.0 for f in д.values()]
    if not rel: return None
    lo, hi = max(0.0, min(rel) - _ХРОМА_ВНИЗ), min(1.0, max(rel) + _ХРОМА_ВГОРУ)
    return dict(вісь="rel_C", межі=(round(lo, 2), round(hi, 2)), ширина=_ШИРИНА_REL_C,
                ясність_рис={nm: round(f.get("rel_C", 0.0) or 0.0, 2) for nm, f in д.items()},
                джерело="R-MUN-05 (muted↔clear як вісь) + практики (JPCA: 清濁 як 4-й атрибут); "
                        "ширина вікна — T3 з feature_spectrum",
                сила="hint")

def родини(F, source="uncontrolled"):
    """Родини тону від кожної даної риси, впорядковані за рангом риси і тиском.
    Кожна родина: дуга, центр, роль, ранг, тиск R-CHEV-14, атенюація Кіршмана III на L риси."""
    R = cs.reliability(source)
    придатно = R["hue"] >= cs.MIN_TO_EMIT
    д = _дані(F); h_шк = (F.get("шкіра") or {}).get("h"); L_шк = (F.get("шкіра") or {}).get("L")
    out = []
    for nm, f in д.items():
        рід = рід_риси(nm)
        if not f.get("тон_визначений", True) or f.get("h") is None:
            out.append(dict(риса=nm, рід=рід, роль=РОЛЬ_РИС[рід], ранг=РАНГ_РИС[рід], ахроматична=True,
                            голосує="лише світлотою й хромою", дуги=[]))
            continue
        for rel in ВІДНОШЕННЯ:
            off, w = cs.RELATIONS[rel]
            центри = [(f["h"] + off) % 360] + ([(f["h"] - off) % 360] if off not in (0, 180) else [])
            for c in центри:
                дуга = cs._arc(c, w)
                if h_шк is not None:
                    тиск, _ = cs.тиск_тону(c, h_шк)
                    тиск_L = cs.тиск_тону(c, h_шк, L_речі=f.get("L"), L_шкіри=L_шк)[0]
                else:
                    тиск = тиск_L = None
                out.append(dict(риса=nm, рід=рід, роль=РОЛЬ_РИС[рід], ранг=РАНГ_РИС[рід],
                                відношення=rel, дуга=(round(дуга[0], 1), round(дуга[1], 1)), центр=round(c, 1),
                                температура=("тепла" if 0 <= c < 180 else "холодна"),
                                тиск=тиск, тиск_на_L_риси=тиск_L,
                                hex_риси=f.get("hex")))
    # Порядок усередині риси — ПЕРЕГУК ПЕРШИЙ (analogous), потім split, потім комплемент:
    # практики міжродовідно кажуть «повторюй свої кольори» (Flusser, Zyla, Lamport), і
    # Perrett 2023 знайшов саме перегук (світлі очі → блакитне). Тиск R-CHEV-14 — не
    # критерій «краще» (напрям не встановлений), тому він лише третій ключ.
    _ПОРЯДОК_ВІДН = {"analogous": 0, "split": 1, "complementary": 2}
    out.sort(key=lambda r: (r["ранг"], _ПОРЯДОК_ВІДН.get(r.get("відношення"), 9), -(r.get("тиск") or 0.0)))
    return dict(придатно=придатно, надійність_тону=R["hue"], родини=out,
                утримано=(None if придатно else
                          "абсолютний тон рис не переживає некерований баланс білого (K-PC-05): "
                          "родини порахувані, але у фід не йдуть; світлота й хрома — йдуть"))

def нейтралі(F):
    """«Її нейтралі» — від волосся (Zyla: другий і третій base) і шкіри («свій білий»).
    Температура нейтралі — по b* риси проти єдиних порогів outfit.C['b_нейтралі']."""
    д = _дані(F); тепла, холод = O.C["b_нейтралі"]
    out = []
    for nm, f in д.items():
        рід = рід_риси(nm)
        if рід == "очі": continue
        b = f.get("b")
        if b is None: continue
        сім_я = "тепла" if b > тепла else ("холодна" if b < холод else "ахроматична")
        out.append(dict(риса=nm, рід=рід, L=round(f["L"], 1), b=round(b, 1), сім_я=сім_я,
                        роль=("світла_нейтраль" if рід == "шкіра" else
                              ("темна_нейтраль" if f["L"] < 40 else "нейтраль")),
                        b_вікно=((тепла, None) if сім_я == "тепла" else (None, холод) if сім_я == "холодна" else (None, None)),
                        hex=f.get("hex")))
    return out

def макіяж_у_палітрі(F, св, хр, рд):
    """R-MUA-02 (Scaman, 12 Blueprints): макіяж і одяг — з ОДНІЄЇ палітри. K-MUA-01 як було.
    Тут НЕ радиться відтінок (R-MUA-03 — дослідницький шар); повідомляється ПОЗИЦІЯ
    обраного кольору відносно зони даних рис. Сила hint."""
    out = {}
    for nm, f in _обрані(F).items():
        поз = dict(зона=f.get("зона"), hex=f.get("hex"), L=round(f["L"], 1), rel_C=round(f.get("rel_C", 0.0) or 0.0, 2))
        if св: поз["у_смузі_світлоти"] = членство(св, f["L"])
        if хр: поз["у_смузі_хроми"] = членство(хр, f.get("rel_C", 0.0) or 0.0)
        if рд and рд["родини"] and f.get("h") is not None:
            найбл = min((r for r in рд["родини"] if r.get("центр") is not None),
                        key=lambda r: abs((f["h"] - r["центр"] + 180) % 360 - 180), default=None)
            if найбл:
                поз["найближча_родина"] = dict(риса=найбл["риса"], відношення=найбл["відношення"],
                                              Δh=round(abs((f["h"] - найбл["центр"] + 180) % 360 - 180), 1))
        поз["правило"] = "R-MUA-02"; поз["сила"] = "hint"
        поз["суть"] = ("обраний колір лежить у зоні даних рис" if
                       (поз.get("у_смузі_світлоти", 1) > 0.5 and поз.get("у_смузі_хроми", 1) > 0.5)
                       else "обраний колір поза смугою світлоти або хроми даних рис — рядок від нього "
                            "у фід іде з родом «обрана» і знімається окремо")
        out[nm] = поз
    return out

def палітра(F, source="uncontrolled"):
    св, хр, рд = смуга_світлоти(F), смуга_хроми(F), родини(F, source)
    нт = нейтралі(F)
    try:
        import trace as _СЛ
        _СЛ.запис("K-ECHO-01", "ролі рис: волосся→нейтраль, очі→акцент, шкіра→білий", "палітра", значення=len(нт), сила="hint")
        if св: _СЛ.запис("K-CON-01", "її чорний / її білий", "палітра", значення=св["межі"], сила="hint")
        if any(r.get("тиск_на_L_риси") is not None for r in рд["родини"]):
            _СЛ.запис("R-CHEV-19", "атенюація Кіршмана III на тиску тону", "палітра", значення=1, сила="default")
    except Exception:
        pass
    return dict(світлота=св, хрома=хр, родини=рд, нейтралі=нт,
                макіяж=макіяж_у_палітрі(F, св, хр, рд),
                ранги=dict(РАНГ_РИС), ролі=dict(РОЛЬ_РИС),
                провенанс=dict(
                    порядок_рис="T2 · Perrett 2023 (очі > шкіра; шкіра «мало впливу»); білі жінки, екран",
                    ролі_рис="T3 · Zyla 2010, Flusser 2002, Lamport — міжродовідно",
                    смуги="T3 · константи feature_spectrum і K-COL-01",
                    тиск="R-CHEV-14 (T2 форма) × R-CHEV-19 Кіршман III (T1 закон, T4 форма спаду)"),
                статус=("зона в LCh від даних рис; «пасує» НЕ виміряно — вердикту людини нема. "
                        "Ранги — порядок, не ваги; сили — hint"))

def рядки_у_фід(спец):
    """Рядки каталогу З ПАЛІТРИ: (а) нейтралі від волосся/шкіри з b*-вікном і смугою
    світлоти людини, (б) акценти від очей у дугах родин. L і C — від ЛЮДИНИ (смуги),
    перетнуті з вікном слота, а не скопійовані з нього. Кожен рядок несе ранг риси."""
    П = спец.get("палітра")
    if not П: return []
    св, хр = П["світлота"], П["хрома"]
    рядки = []
    for s, v in спец["слоти"].items():
        if v.get("попередження"): continue
        Llo, Lhi = v["L"]
        # перетин смуги світлоти людини з вікном слота; порожній перетин — рядок не фабрикується
        if св:
            Llo, Lhi = max(Llo, св["межі"][0]), min(Lhi, св["межі"][1])
            if Llo > Lhi: continue
        # K-ECHO-01 ОСКАРЖЕНО ВСЕРЕДИНІ ПРАКТИКИ (Nachmias, 12 Blueprints/Sci\ART, 2014/2023):
        # «"це пасує до мого волосся" — очевидно хибно для багатьох холодних людей з
        # карими очима й каштановим волоссям: теплі землисті кольори виявляють
        # плямистість, якої нема в правильних (холодніших)»; у Sci\ART волосся на
        # аналізі ЗАКРИВАЮТЬ — обертон волосся ≠ підтон шкіри. Тому b*-вікно нейтралі
        # від волосся діє лише коли бік шкіри (палітра_практична.осі.hue) не проти нього.
        _hue = ((спец.get("палітра_практична") or {}).get("осі") or {}).get("позиція", {}).get("hue", 0.0)
        for н in П["нейтралі"]:
            _проти = ((н["сім_я"] == "тепла" and _hue < -0.125) or (н["сім_я"] == "холодна" and _hue > 0.125))
            # стеля хроми нейтралі — та сама, що в коридорах outfit.нейтраль (тепла до 34)
            r = dict(слот=s, L_min=Llo, L_max=Lhi, C_min=0.0,
                     C_max=max(O.C["warm_neutral"][2], O.C["cool_neutral"][2]),
                     h_from=None, h_to=None, нейтраль=True,
                     роль="нейтраль_від_%s" % н["рід"], ранг_риси=РАНГ_РИС[н["рід"]],
                     джерело_тону="палітра:%s" % н["риса"], сім_я=н["сім_я"],
                     чому=("нейтраль від риси «%s» (b*=%.1f → %s сім'я): Zyla «свій %s»; світлота — "
                           "смуга людини ∩ вікно слота" % (н["риса"], н["b"], н["сім_я"],
                                                          "чорний" if н["роль"] == "темна_нейтраль" else
                                                          "білий" if н["роль"] == "світла_нейтраль" else "коричневий/хакі")))
            if _проти:
                r["чому"] += " · b*-вікно від волосся ЗНЯТО: бік шкіри протилежний (Nachmias: обертон ≠ підтон)"
                r["оскаржено"] = "K-ECHO-01/Nachmias"
            else:
                if н["b_вікно"][0] is not None: r["b_min"] = н["b_вікно"][0]
                if н["b_вікно"][1] is not None: r["b_max"] = н["b_вікно"][1]
            рядки.append(r)
        if "сім_я" in v: continue                       # кольорові рядки — лише в кольорові слоти
        if not П["родини"]["придатно"]: continue
        Clo, Chi = v["C"]
        for р in П["родини"]["родини"]:
            if р.get("дуга") is None or р["рід"] != "очі": continue   # акценти — від очей (ранг 1)
            рядки.append(dict(слот=s, L_min=Llo, L_max=Lhi, C_min=Clo, C_max=Chi,
                              h_from=р["дуга"][0], h_to=р["дуга"][1], нейтраль=False,
                              роль="акцент_від_очей", ранг_риси=р["ранг"],
                              джерело_тону="палітра:%s:%s" % (р["риса"], р["відношення"]),
                              тиск_центр=р.get("тиск"), тиск_на_L=р.get("тиск_на_L_риси"),
                              чому=("акцент від очей у відношенні «%s» до тону райдужки: очі — риса рангу 1 "
                                    "(Perrett 2023); L — смуга людини ∩ слот" % р["відношення"])))
    рядки.sort(key=lambda r: r.get("ранг_риси", 9))
    return рядки

def словами(П):
    """Палітра людською мовою — для брифу. Нічого не стверджує про «пасує»."""
    if not П: return ""
    св, хр = П["світлота"], П["хрома"]
    ч = []
    if св:
        ч.append("Ваша смуга світлоти: від «вашого чорного» (%s, L*%.0f) до «вашого білого» (%s, L*%.0f)."
                 % (св["її_чорний"]["риса"], св["її_чорний"]["L"], св["її_білий"]["риса"], св["її_білий"]["L"]))
    if хр:
        lo, hi = хр["межі"]
        ч.append("Ясність: %s (%.2f–%.2f відносної хроми)." %
                 ("приглушена" if hi < 0.5 else "ясна" if lo > 0.45 else "середня", lo, hi))
    нт = П["нейтралі"]
    if нт:
        ч.append("Ваші нейтралі: " + "; ".join("%s від %s (%s, L*%.0f)" %
                 ("темна" if n["роль"] == "темна_нейтраль" else "світла" if n["роль"] == "світла_нейтраль" else "середня",
                  n["риса"], n["сім_я"], n["L"]) for n in нт) + ".")
    рд = [r for r in П["родини"]["родини"] if r.get("дуга") and r["рід"] == "очі"]
    if рд:
        ч.append("Акценти від очей: " + "; ".join("%s %d–%d° (тиск %.2f)" %
                 (r["відношення"], r["дуга"][0], r["дуга"][1], r.get("тиск") or 0) for r in рд[:3]) + ".")
    elif not П["родини"]["придатно"]:
        ч.append("Тон рис із цього фото не стверджується (K-PC-05) — акценти від очей утримано.")
    for nm, m in П["макіяж"].items():
        ч.append("Макіяж (%s): %s." % (m["зона"], m["суть"]))
    return " ".join(ч)
