"""ПЕРСОНАЛЬНА ПАЛІТРА: зона в LCh, виведена з РИС людини, — а не пара назв кольорів.

ЧОГО НЕ БУЛО (виміряно на фіді Ager і прочитано в коді):
  · риси давали дуги тону рівноправними рядками без рангу й без ролі — кожна дуга
    йшла в кожен слот як «домінанта»;
  · світлота й хрома людини у фід не доходили: рядок від риси брав L і C зі
    ВІКНА СХЕМИ, а «її чорний» / «її білий» / «її ясність» ніде не існували;
  · макіяж входив як риса з окремою дугою, але ніхто не питав, чи він узагалі
    лежить у зоні людини (R-MUA-02: одна палітра на одяг і макіяж).

ЩО ЦЕ (три осі корпусу, R-MUN-05, як ЗОНА, а не сезон):
  смуга світлоти  — від найтемнішої даної риси до найсвітлішої (± крок K-COL-01);
                    «її чорний» = найтемніша риса, «її білий» = найсвітліша;
  смуга хроми     — від ясності даних рис (rel_C), тими ж константами, що
                    feature_spectrum (T3);
  родини тону     — від кожної даної риси: перегук (analogous), комплемент, split —
                    із силою тиску R-CHEV-14 і атенюацією Кіршмана III (R-CHEV-19).

РАНГ РИС — ПОРЯДОК, НЕ ВАГИ. Perrett 2023 (Psychol. Aesth. Creat. Arts 19(5):1099,
doi 10.1037/aca0000626): очі пересаджено між обличчями — вибір кольору одягу пішов
за очима; трансформація шкіри між рівнями меланіну вибору не зрушила. Це дає ПОРЯДОК
очі > волосся ≈ шкіра (T2). Числових ваг жодне джерело не дає — тому тут ранги, а
не коефіцієнти: вигадати 0.6 і 0.4 означало б видати оцінку за вимір.

РОЛІ РИС — практики, міжродовідно (T3): Zyla («Color Your Style»): кільце райдужки →
формальна темна нейтраль («свій чорний»), темне волосся → «свій коричневий», світле
волосся → «свій хакі», райдужка → акценти, шкіра → «свій білий»; Flusser (Dressing the
Man): повторення тонів обличчя в речах поруч; Lamport: «чим більше річ нагадує тебе,
тим краще». Розходження про ПОРЯДОК (Flusser: шкіра перша) розв'язано виміром
Perrett на користь очей — з умовою відстані розмови.

⚠ ЧОГО ТУТ НЕ СТВЕРДЖУЄТЬСЯ. Що зона — «кольори, які вам пасують». Жодна жінка не
сказала «носитиму» про річ, обрану з неї. Зона — «кольори у названих відношеннях до
ваших рис, упорядковані за виміряною важливістю рис». Сила кожного числа — hint.
"""
