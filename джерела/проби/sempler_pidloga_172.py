# -*- coding: utf-8 -*-
"""Рядок 172: підлога слота в семплері бюджету. Коли пакет не влазить у бюджет і
K падає нижче суми підлог, дільба йшла ПРОПОРЦІЙНО наявному — тобто найбагатшим
слотам, а дрібні (кольє, браслет, сережки) майже переставали доїжджати до моделі
саме тоді, коли пул великий.

Два виміри на кожну сцену. Бюджет 120 000 (як у показі): підлога 20 мусить
триматись — контроль, що нічого не зламано. Бюджет 80 000: K падає нижче суми
підлог, і підлога МУСИТЬ зменшитись ОДНАКОВО ДЛЯ ВСІХ — жоден слот не менший за
найбільший (±1 на роздачу лишку), поки в пулі є кандидати.
Запуск із теки `джерела`: python3 проби/sempler_pidloga_172.py"""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge as B, feed as Ф, семплер as С, стенд_знімок as СЗ
КАТ, База, зла = Ф.каталог_на_диску("каталог_повний.xml"), json.load(open("стенд_вх.json", encoding="utf-8")), 0
for назва, сцен in СЗ.СЦЕНАРІЇ.items():
    for бюджет, підлога in ((120000, С.ПІДЛОГА_СЛОТА), (80000, None)):
        з = json.loads(B.виклик("запити", json.dumps(
            dict(База, каталог=КАТ, сценарій=сцен, випадок=назва, бюджет_символів=бюджет), ensure_ascii=False)))
        ст, кнд = (з.get("стеля") or {}), (з.get("кандидати") or {})
        пул = {с: (о or {}).get("рядків") or 0 for с, о in (ст.get("осі") or {}).items() if (о or {}).get("рядків")}
        пак = {с: len(кнд.get(с) or []) for с in пул}
        пд = підлога if підлога else max(пак.values()) - 1     # спільна підлога цього зрізу
        біда = {с: (пак[с], min(пд, пул[с])) for с in пул if пак[с] < min(пд, пул[с])}
        зла += len(біда)
        print("%-20s бюджет %6d · K %s · слотів %2d · підлога %d · нижче неї %d%s\n    %s"
              % (назва, бюджет, ст.get("K", "без зрізу"), len(пак), пд, len(біда),
                 ("" if not біда else " ← " + "; ".join("%s %d<%d" % (с, a, b) for с, (a, b) in sorted(біда.items()))),
                 " · ".join("%s %d/%d" % (с, пак[с], пул[с]) for с in ("верх", "взуття", "кольє", "браслет", "сережки") if с in пул)))
# ── ДРУГЕ ПИТАННЯ НАРЯДУ: чи зсув пулу на кілька рядків перекидає склад ─────
# Пошук K уже бінарний; розрив сидів у `квоти` — на межі «суми підлог» дільба
# стрибком міняла правило. Тут той самий пул проганяється по всіх сусідніх K.
крок = max((sum(abs(С.квоти(пул, K)[с] - С.квоти(пул, K - 1)[с]) for с in пул), K)
           for K in range(2, sum(пул.values()) + 1))
print("ВИСНОВОК: слотів нижче спільної підлоги (поки в пулі є кандидати) — %d; "
      "найбільший зсув складу між сусідніми K на цьому пулі — %d %s (на K=%d)"
      % (зла, крок[0], "речей" if крок[0] % 10 != 1 else "річ", крок[1]))
sys.exit(1 if зла else 0)
