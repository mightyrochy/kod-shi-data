"""Рядок 5661 (клас Б3): вибірка для очей. З 1 227 записів, де слово крамниці хроматичне, а вимір з фото — без тону,
детерміновано (сід 5661) бере 40 пропорційно шарам «сім'я слова × темний (L* < 25) / ні» (найбільші остачі) і друкує
JSON-рядок на річ: id, слово, вимір, L*, кадр жнив зі збагачення (`фото`) і чи він серед кадрів картки
(`фід_фото.кадри_речі`), кадри картки. Сім'ю слова рахує проба (міра), не продукт.
Запуск: cd джерела && python3 -W ignore проби/темні_вибірка_5661.py"""
import collections, json, os, random, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as FK, фід_фото as ФФ, verify as V, colorspace as CS
К = FK._прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"]
оф = {o["id"]: o for o in feed.читати_yml(feed.каталог_на_диску("каталог_повний.xml"))[0]}
зб, сп, хо = feed.читати_збагачення(), ФФ._спільні_фото(list(оф.values())), ФФ._хости_крамниць(list(оф.values()))
def сім(сл):
    ім = (V.слово_крамниці(сл or "") or {}).get("ім")
    return V.сім_я_слова(ім) if ім else None
АХРОМ, шари = {"чорна", "сіра", "світла нейтраль"}, collections.defaultdict(list)
for r in К:
    кр = сім(r.get("колір_назва_крамниці")) if r.get("колір_hex_фото") else None
    if кр and кр not in АХРОМ and V.сім_я_слова(r.get("колір_назва_фото")) in АХРОМ:
        шари[(кр, CS.lch(CS.hx(r["колір_hex_фото"]))[0] < 25)].append(r)
усього, Н = sum(map(len, шари.values())), 40
частки = {ш: Н * len(в) / усього for ш, в in шари.items()}
квота = {ш: int(ч) for ш, ч in частки.items()}
for ш in sorted(частки, key=lambda ш: (int(частки[ш]) - частки[ш], str(ш)))[:Н - sum(квота.values())]:
    квота[ш] += 1
рнд = random.Random(5661)
print("ФАКТ · у вибірці %d з %d; шари: %s" % (Н, усього, sorted((ш[0], ш[1], к) for ш, к in квота.items() if к)))
for ш in sorted(шари, key=str):
    for r in рнд.sample(sorted(шари[ш], key=lambda r: r["id"]), квота[ш]):
        з = зб.get(r["id"]) if isinstance(зб.get(r["id"]), dict) else {}
        о = оф.get(r["id"]) or {"id": r["id"], "фото": r.get("фото") or []}
        кадри = ФФ.кадри_речі(о, сп.get(о.get("магазин")) or {}, хо, з.get("фото"))
        print(json.dumps({"id": r["id"], "назва": r.get("назва"), "слово": r.get("колір_назва_крамниці"),
            "сім'я": ш[0], "темна": ш[1], "вимір": [r.get("колір_назва_фото"), r["колір_hex_фото"]],
            "L": round(CS.lch(CS.hx(r["колір_hex_фото"]))[0], 1), "кадр_жнив": з.get("фото"),
            "кадр_жнив_у_картці": bool(з.get("фото")) and any(ФФ._файл_фото(к) == ФФ._файл_фото(з["фото"]) for к in кадри),
            "кадри": кадри, "фото_фіду_без_картки": [] if кадри else (о.get("фото") or [])[:4]}, ensure_ascii=False))
