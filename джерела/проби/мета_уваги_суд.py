# -*- coding: utf-8 -*-
"""Ц-2: чи мета «експресія» СУДИТЬ готовий образ і чи має ремонт чим лагодити. 5 сідів.
ДО (main 8a69ede): «увагу не тримає ніщо» = плоский hint 0.25 без `запит` — ні крок вибору, ні
вітрина ремонту її не бачили. ПІСЛЯ: сила — вимір смугою K-KOH-08 з `формальність`, запит у слот
акценту схеми, свідки «собою» ті самі, що в «приховати». Образи: 10 заглушки + найтихіший пулу.
Прогін: cd джерела && python3 проби/мета_уваги_суд.py"""
import json, sys, pathlib; sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import feed as Ф, bridge as B, pipeline as ПЛ, регістр_уваги as РУ
from композитор_річ import _у_річ   # той самий будівник речі, що в композиторі
СЦ = dict(нагода="свято", місце="клуб", година=21, темп_c=20)
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
вх.update(каталог=Ф.каталог_на_диску("каталог_повний.xml"), гілка=0, сценарій=СЦ, випадок="вечірка",
          паспорт=dict(СЦ, подія="вечірка", ошатність=[6, 8], мета="експресія", мета_слова="хочу, щоб усі помітили"))
СТ = РУ.стеля(); разом = [0, 0, 0, 0.0, 0]; тихі = РУ.смуги()["тихі"]; ТИХІ_СЛОТИ = ("верх", "низ", "взуття", "сумка")
знах = lambda F, р, T, kw: [z for ст in (ПЛ.перевірити_образ(F, р, тіло=T, **kw).get("стани") or {}).values()
                            for z in (ст or []) if isinstance(z, dict) and z.get("правило") == РУ.ПРАВИЛО]
print("сцена %s · стеля %.0f · тиха смуга %s" % (json.dumps(СЦ, ensure_ascii=False), СТ, тихі))
for сід in (3, 5, 7, 11, 13):
    r = json.loads(B.виклик("запити", json.dumps(dict(вх, сід=сід), ensure_ascii=False)))
    к = r.get("кандидати") or {}; за_ід = {x["id"]: x for x in B.каталог_останнього_пакета()}
    F, T, _з, kw = B._збірка(B._нормалізувати_вхід(B._застосувати_паспорт(dict(вх, сід=сід))))
    г = lambda i: (РУ.гучність_уваги(*РУ._L_C(за_ід.get(i) or {})) if РУ._L_C(за_ід.get(i) or {})[0] is not None else None)
    ід_с = lambda x: x.get("id") or x.get("ід"); бр = lambda с, i: (ід_с(к[с][i % len(к[с])]) if к.get(с) else None)
    тихо = lambda с: (sorted([ід_с(x) for x in (к.get(с) or []) if г(ід_с(x)) is not None], key=г) or [None])[0]
    ф = до = з = зап = 0; сум = 0.0
    for i in range(11):      # 0 — найтихіший образ пулу, 1–10 — образи заглушки
        ід = ([тихо(с) for с in ТИХІ_СЛОТИ] if not i else
              (([бр("сукня", i)] if (к.get("сукня") and i % 2) else [бр("верх", i), бр("низ", i)])
               + [бр("взуття", i), бр("сумка", i), бр("прикраси", i)]))
        речі = [_у_річ(dict(за_ід[x]), за_ід[x].get("слот") or "верх", T) for x in ід if x in за_ід]
        зн = знах(F, речі, T, dict(kw)); гг = [x for x in (г(r_["id"]) for r_ in речі) if x is not None]
        ф += any(x > СТ for x in гг); до += bool(гг) and not any(x > СТ for x in гг); з += len(зн)
        зап += sum(1 for z in зн if (z.get("вікно") or z.get("запит_у_каталог"))); сум += sum(z.get("сила_нп") or 0.0 for z in зн)
    print("  сід %2d: фокус %2d/11 · ДО %d знахідок (0.25 кожна, 0 запитів) → ПІСЛЯ %d (сума сил %.2f, із запитом %d)" % (сід, ф, до, з, сум, зап))
    разом = [разом[0] + ф, разом[1] + до, разом[2] + з, разом[3] + сум, разом[4] + зап]
в = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, сід=13,
    ід=[x for x in (тихо(с) for с in ТИХІ_СЛОТИ) if x]), ensure_ascii=False)))
print("РАЗОМ 55 образів: фокус %d · ДО %d (сума сил %.2f, запитів 0) → ПІСЛЯ %d (сума сил %.2f, запитів %d)"
      " · слоти ремонту з мети %s · вітрина %s" % (разом[0], разом[1], 0.25 * разом[1], разом[2], разом[3],
      разом[4], РУ.слоти_ремонту(в.get("образи")), sorted((в.get("вердикт") or {}).get("вітрина") or {})))
