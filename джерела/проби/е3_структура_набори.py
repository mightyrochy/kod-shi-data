"""Повний каталог і граничні входи восьми емісій `аксесуари_структура` для звірки ваги."""
import gzip, json, os, pathlib


def набори(А):
    """Ті самі входи без моделі: кожна річ каталогу в кожному з семи емітентів файлу."""
    import feed as Ф
    import outfit as О
    кеш = pathlib.Path(os.environ.get('TMP') or '/tmp') / 'е3_каталог.json.gz'
    if not кеш.exists():
        каталог = Ф.база_прогону(Ф.каталог_на_диску('каталог_повний.xml'), ліміт_фото=0)['каталог']
        with gzip.open(кеш, 'wt', encoding='utf-8') as ф:
            json.dump(каталог, ф, ensure_ascii=False)
    каталог = json.load(gzip.open(кеш, 'rt', encoding='utf-8'))
    гучні, кошики = [], set()       # партнери K-ACC-01: перша гучна сукня/верх у кожних 60° тону
    for р in каталог:
        м = А._КР.межі_кольору(р)
        if р.get('слот') in ('сукня', 'верх') and А.гучна_речі(р) == 'так' and м and м[4]:
            if int(м[4][0] // 60) not in кошики:
                кошики.add(int(м[4][0] // 60)); гучні.append(р)
    спец = {'палітра_практична': {'найдальші': {'вікна': {'L': [30, 60], 'C': [10, 40]}}}}
    окуляри = [{'слот': 'окуляри', 'id': 'g1'}, {'слот': 'окуляри', 'id': 'g2', 'пар_більше_однієї': True}]
    за_слотом = {}
    for і, р in enumerate(каталог):
        н = str(р.get('id'))
        for ф in ('масштаб_аксесуара', 'асиметрія_інтересу', 'місце_не_обране', 'формат_хустки'):
            yield н, ф, [[р]], {}
        if р.get('слот') in А.СЛОТИ_АКСЕСУАРІВ:
            for п in гучні:
                yield н + '+' + str(п.get('id')), 'аксесуар_як_структура', [[р, п]], {}
            гр = за_слотом.setdefault(р['слот'], [])
            for к in (1, 2):
                if len(гр) >= к:
                    yield н + '×%d' % (к + 1), 'віднімання', [О.елементи(гр[-к:] + [р], стан='надворі')], {}
            гр[:] = (гр + [р])[-2:]
        if р.get('слот') == 'шарф':
            yield н, 'рятівник_приобличчя', [спец, [{'слот': 'верх'}]], {'носій': р}
    for о in окуляри:
        yield о['id'], 'рятівник_приобличчя', [спец, [{'слот': 'верх'}]], {'носій': о}
