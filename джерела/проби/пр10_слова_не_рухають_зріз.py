# -*- coding: utf-8 -*-
"""ПР-10 (рядок 249): СЛОВА ПРОМПТА НЕ РУХАЮТЬ ЗРІЗ ПУЛУ.

Доти бюджет 120 000 міряв ВЕСЬ промпт (~260 симв. = 1 річ), і лише нота слота мала резерв
(#451, проба `ч10_форма_нот_не_рухає_зріз.py` — її місце зайняла ця). Тепер бюджет міряє
лише перелік речей (`пакет_моделі.вага_пулу`). Проба МІРЯЄ: той самий стенд прогоняється
чинним, з правилами складання, довшими на 5 000 символів, і з нотою, довшою на 3 000 (доти
за резервом). Мусить бути: K і склад пулу побайтово ті самі; росте лише запит.
Запуск із `джерела`: python3 проби/пр10_слова_не_рухають_зріз.py"""
import dataclasses, hashlib, json, os, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent)); os.chdir(sys.path[0])
import bridge as B, feed as F, внутрішня_мова as ВМ, міст_пакет as МП, пакет_моделі as ПМ
вх0 = dict(json.load(open("стенд_вх.json", encoding="utf-8")), сід=3,
           каталог=F.каталог_на_диску("каталог_повний.xml"))
ЗАЯВИ, СКЛ = dict(ВМ.ЗАЯВИ), ПМ.СКЛАДАННЯ
відпис = lambda п: hashlib.md5(json.dumps(sorted(
    r.get("id") for сл in (п or {}).values() for r in сл), ensure_ascii=False).encode()).hexdigest()[:12]


def прогін(правила=0, нота=0):
    """Пакет руки 1, коли правила складання довші на `правила`, а кожне визначення заяви — на `нота`."""
    ВМ.ЗАЯВИ.clear(); ВМ.ЗАЯВИ.update({к: (v + " " + "x" * нота) if (isinstance(v, str) and нота) else v
                                       for к, v in ЗАЯВИ.items()})
    ПМ.СКЛАДАННЯ = dataclasses.replace(СКЛ, правила=СКЛ.правила + (("x" * правила,) if правила else ()))
    МП._КЕШ_ПАКЕТА.clear()      # ключ кешу — входи, а тексти промпта в ньому не стоять
    вих = json.loads(B.виклик("запити", json.dumps(вх0, ensure_ascii=False)))
    ст = вих.get("стеля") or {}
    return ст.get("K"), ст.get("пул_символів"), ст.get("символів"), відпис(вих.get("кандидати"))


K0, п0, с0, в0 = прогін()
зсувів = 0
for назва, кв in (("правила +5 000", dict(правила=5000)), ("нота +3 000", dict(нота=3000))):
    K, п, с, в = прогін(**кв)
    зсувів += (K, в) != (K0, в0)
    print("%-15s K %s → %s · перелік %s → %s · запит %s → %s · склад пулу %s → %s"
          % (назва, K0, K, п0, п, с0, с, в0, в))
прогін()
print("ЗСУВІВ ЗРІЗУ ВІД СЛІВ ПРОМПТА: %d (мусить 0) · бюджет переліку речей %d" % (зсувів, МП._БЮДЖЕТ_СИМВОЛІВ))
