"""`відповідь_сира` другого виклику рук 3–4 несе ПРОЗУ, а не перелік моделі.

Наслідок: у звіті власника нема жодного сліду того JSON-списку, за яким код
склав картку, — «назвала 6 → на картці 5» перевірити нічим."""
import json, os
Ф = os.path.join(os.path.dirname(__file__), "..", "..", "аудит", "тести",
                 "власник_2026-09-25", "verdykty-0phxvk-2026-09-25-2012.json")
d = json.load(open(Ф, encoding="utf-8"))
for п in d["прогони"]:
    for в in п["вердикти"]:
        в_ = (в.get("етапи") or {}).get("виклики") or []
        if len(в_) < 2:
            continue
        чого = [(c.get("запит") or {}).get("чого") or "?" for c in в_]
        if not any("перелік" in x or "випиши" in x for x in чого):
            continue
        print("прогін %s · рука %s" % (п["спільне"].get("розклад"), в["рука"]))
        for c in в_:
            с = c.get("відповідь_сира") or ""
            print("  %-46s відповідь %5d симв | починається: %s"
                  % (((c.get("запит") or {}).get("чого") or "?")[:46], len(с),
                     (с[:58].replace("\n", " ") + "…")))
        a, b = (в_[0].get("відповідь_сира") or ""), (в_[1].get("відповідь_сира") or "")
        print("  відповіді 1 і 2 однакові: %s" % ("ТАК — перелік у файл не записано" if a == b else "ні"))
        діаг = [x for x in ((в.get("етапи") or {}).get("діагноз_руки") or []) if "назвала" in x]
        for x in діаг:
            print("  діагноз: %s" % x)
