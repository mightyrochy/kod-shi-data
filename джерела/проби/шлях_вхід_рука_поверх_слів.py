# -*- coding: utf-8 -*-
"""Розбір 1/8 (вхід і сценарій): НЕТОРКАНЕ ТИПОВЕ ПОЛЕ ФОРМИ ЗАТИРАЄ ЧИСЛО, ЯКЕ ЖІНКА НАЗВАЛА.
`паспорт_нагоди.поля_рукою` вважає «рукою» будь-яке поле-плитку, що НЕ ЗБІГАЄТЬСЯ з паспортом
досі, — зокрема дефолти 11:00 і 18 °C, яких вона не торкалась. Цикл «рука» стоїть ПІСЛЯ гейта
чисел, тож перебиває і число моделі, і її власне слово, і нічого не пише в `не_взято_кодом`.
Запуск із теки `джерела`: `python3 проби/шлях_вхід_рука_поверх_слів.py`."""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import паспорт_нагоди as ПН

слова = "ввечері о сьомій, надворі +6"
відповідь = json.dumps({"година": 19, "темп_c": 6}, ensure_ascii=False)
досі = {"година": 19, "темп_c": 6, "нагода": "свято"}        # паспорт, який уже почув її слова
print("її слова: «%s» → код сам читає: година %s, темп %s"
      % (слова, ПН.сказано_про("година", слова), ПН.темп_зі_слів(слова)))
for підпис, сц in (("форма НЕТОРКАНА (дефолти показу)", {"година": 11, "темп_c": 18}),
                   ("форми в цьому виклику нема зовсім", {})):
    п = ПН.паспорт_з_json(відповідь, сц, слова, паспорт_досі=досі)
    print("\n%s → поля_рукою=%s" % (підпис, ПН.поля_рукою(сц, досі)))
    print("   паспорт: година=%s темп_c=%s джерело_полів=%s"
          % (п["година"], п["темп_c"], json.dumps(п["джерело_полів"], ensure_ascii=False)))
    print("   не_взято_кодом: %s" % json.dumps(п.get("не_взято_кодом"), ensure_ascii=False))
    print("   випадок жінці: «%s»" % ПН.паспорт_рядком_людині(п))
print("\nпорядок у `паспорт_з_json`: гейт чисел (`сказано_про`, ~р.1929) → її число (`темп_зі_слів`, ~р.1943)"
      " → цикл ПОЛЯ_ПЛИТОК «рука» (~р.1966), останній і виграє")
