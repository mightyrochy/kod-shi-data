# -*- coding: utf-8 -*-
"""K-CRA-01 (третя річ) на живому шляху: `python3 проби/cra_K-CRA-01.py`.

ЧОМУ БУВ «ЛИШЕ СЛІД»: єдиним місцем правила був рядок брифа
(`brief.ПРАВИЛО_РЯДКА["третя_річ"]`), а `brief.дод` пише `trace.запис` і НЕ повертає
знахідки. Образ «сукня + взуття» виходив із суду без жодного слова про те, що він
«одягнений», а не «стилізований». Тепер це знахідка `суд_образу.третя_річ`, і вона
їде у вердикт відром `ремесло`. Проба показує ОБИДВІ половини: без третьої речі
рядок є, з нею — зникає."""
import sys, pathlib, json
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B

вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["гілка"] = 0
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
пул = json.loads(r["руки"]["1"])["пул"]
взяті = set()


def перший(слот):
    for к in (пул.get(слот) or []):
        if к["н"] not in взяті:            # одна річ не може стояти у двох слотах
            взяті.add(к["н"]); return к["н"]


def рядок(речі):
    вд = json.loads(B.виклик("від_моделі", json.dumps(dict(
        вх, текст_моделі=json.dumps({"версія": "1", "образи": [
            {"ід": "о1", "речі": речі}]}, ensure_ascii=False)), ensure_ascii=False)))
    о = ((вд.get("вердикт") or {}).get("образи") or [{}])[0]
    return next((z for z in (о.get("знахідки") or []) if z["правило"] == "K-CRA-01"), None)


база = [перший("сукня"), перший("взуття")]
третя = перший("шарф")
print("база:", база, "· третя річ:", третя)
без = рядок(база)
print("K-CRA-01 на «сукня + взуття»:", "НЕМА" if not без else
      "%s %.2f · %s" % (без["сила"], без["сила_нп"], без["суть"][:58]))
print("  речі рядка:", (без or {}).get("речі"), "· регістр", (без or {}).get("регістр"))
з = рядок(база + [третя])
print("K-CRA-01 після додавання шарфа:", "НЕМА — саме так" if not з else з["суть"])
assert без and not з, (без, з)
