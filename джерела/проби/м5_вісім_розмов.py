# -*- coding: utf-8 -*-
"""М-5 п.8: 8 багатоходових розмов з уточненнями й посиланнями на попереднє (`м5_розмови.json`), паспорт проти
очікуваного після КОЖНОГО ходу. «До» — перекладач бачить лише слова ходу, сторож звіряє лише їх; «після» — хід
розмови (розмова, паспорт, профіль), сторож — усі її репліки. Без MODEL — сумлінна модель із фікстури (стеля
архітектури); з MODEL — жива (`мова_спільне`). Друкує ✓/✗, виклики мовної моделі й секунди. Запуск: cd джерела && [MODEL=… MODEL_URL=…] python3 проби/м5_вісім_розмов.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import мова_спільне as С
М, Ж, разом = С.М, bool(С.МОДЕЛЬ), {"до": [0, 0, 0, 0.0], "після": [0, 0, 0, 0.0]}
def так(п, ч, частини):
    зн = next(з for з in ("∌", "∋", "=") if з in ч); поле, v = ч.split(зн, 1); знач = частини if поле == "need" else п
    for к in поле.split("."): знач = знач.get(к) if isinstance(знач, dict) else None
    return (str(знач) == v or (isinstance(знач, float) and str(int(знач)) == v)) if зн == "=" else ((v in (знач or [])) == (зн == "∋"))
for р in json.load(open(os.path.join(С.ТУТ, "м5_розмови.json"), encoding="utf-8")):
    print(р["назва"])
    for бік in ("до", "після"):
        п, історія, її, теми, підс, хиби = {}, [], [], [], [0, 0, 0, 0.0], []
        for х in р["ходи"]:
            її.append(х["вона"]); с = 0.0
            if Ж and бік == "до":
                відп, с = С.модель(М.промпт_входу("scenario", х["вона"], {"offered_topics": теми} if теми else None))
                дельта = М.прийняти_вхід("scenario", відп)["внутрішня"]; частини = {"need": дельта.get("question_about") or ("look" if дельта.get("question") else "none")}
            elif Ж:
                відп, с = С.модель(М.промпт_розмови({"розмова": {"нове": х["вона"], "історія": історія}, "сценарій": {}, "паспорт": п}))
                рр = М.прийняти_розмову(відп); дельта, частини = рр["внутрішня"], рр["частини"]
            else:
                дельта = М.прийняти_вхід("scenario", json.dumps(х.get(бік, х.get("обидва"))))["внутрішня"]
                частини = {"need": х.get("до_питання_до", "none")} if бік == "до" else {"need": "none", "text": "Записала."}
            ш = json.loads(М.мова(dict({"паспорт_з": дельта, "сценарій": {}, "паспорт": п},
                                       **({"слова_ходу": х["вона"]} if бік == "до" else {"слова_розмови": її, "частини": частини}))))
            п, теми, питання = ш["паспорт"], ш["теми_поради"], частини.get("need") in ("app", "look")
            історія += [{"хто": "людина", "текст": х["вона"]}, {"хто": "ші", "текст": ш.get("текст") or "Записала."}]
            добрі = [так(п, ч, частини) for ч in х["чекаємо"]]
            хиби += ["хід %d: %s" % (len(її), ч) for ч, д in zip(х["чекаємо"], добрі) if not д]
            підс = [підс[0] + sum(добрі), підс[1] + len(добрі), підс[2] + ((2 + питання) if бік == "до" else (1 + 2 * питання)), підс[3] + с]
        разом[бік] = [a + b for a, b in zip(разом[бік], підс)]
        print("   %s ✓%d/%d, викликів %d%s%s" % (бік, підс[0], підс[1], підс[2], " · %.0f с" % підс[3] if Ж else "", (" ✗ " + "; ".join(хиби)) if хиби else ""))
print("\nРАЗОМ (%s): %s" % ("жива модель " + С.МОДЕЛЬ if Ж else "сумлінна модель з фікстури", " · ".join(
    "%s ✓%d/%d, викликів %d%s" % (б, *разом[б][:3], " · %.0f с" % разом[б][3] if Ж else "") for б in ("до", "після"))))
sys.exit(0 if Ж or разом["після"][0] == разом["після"][1] else 1)
