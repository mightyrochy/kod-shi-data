"""Реєстр А (рядок 5630), клас А9: речі, чиє фото не дало придатного запису збагачення
(`_збагачення_придатне` = ні) — колір і поля з фото втрачено. Друкує причини: помилка запису
(усі фото — заглушки чи не скачались), впевненість нижче порога, колір поза лексиконом; окремо —
речі каталогу без запису збагачення і записи збагачення для id, яких у каталозі вже нема.
Запуск: cd джерела && python3 проби/каталог_проблеми_а_непридатне.py"""
import collections, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed as Ф, verify as V
from фід_збагачення import _збагачення_придатне, ЗБАГАЧЕННЯ_ПОРІГ
оф = Ф.читати_yml(Ф.каталог_на_диску("каталог_повний.xml"))[0]
зб = Ф.читати_збагачення()
причини, крамниці = collections.Counter(), collections.Counter()
for o in оф:
    з = зб.get(o["id"])
    if _збагачення_придатне(з):
        continue
    п = ("нема запису" if not isinstance(з, dict) else "помилка: " + str(з["помилка"])[:40] if "помилка" in з
         else "впевненість < %.2f" % ЗБАГАЧЕННЯ_ПОРІГ if (з.get("впевненість") or 0) < ЗБАГАЧЕННЯ_ПОРІГ
         else "колір поза лексиконом")
    причини[п] += 1; крамниці[o.get("магазин")] += 1
print("непридатне збагачення: %d з %d ·" % (sum(причини.values()), len(оф)), dict(причини.most_common(8)))
print("  по крамницях:", крамниці.most_common(8))
ід = {o["id"] for o in оф}
print("записів збагачення для id поза каталогом: %d з %d" % (sum(1 for к in зб if к not in ід), len(зб)))
