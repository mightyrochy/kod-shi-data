"""Знімок кожної ваги воріт розміру аксесуарів; другий аргумент — коміт ДО."""
import collections, gzip, json, pathlib, sys
КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРІНЬ / 'джерела'))
sys.path.insert(0, str(КОРІНЬ / 'джерела/проби'))


def main():
    """Записати склад, силу, `блокує`, сиру й обмежену вагу та відсів воріт для кожного входу."""
    if len(sys.argv) > 2:
        from виконання.е3_база import встановити
        встановити(sys.argv[2], ('аксесуари_розмір',))
    import аксесуари_розмір as А
    from е3_розмір_набори import набори
    from реєстр_сила import обмежити_вагу
    вих, підсумок = [], collections.Counter()
    for назва, речі, профіль in набори():
        лишились, з1 = А.ворота_розміру({"аксесуарні": профіль}, [dict(р) for р in речі])
        відсів = sorted(р["id"] for р in речі if р["id"] not in {л["id"] for л in лишились})
        for функція, знахідки in (("ворота_розміру", з1), ("ширина_й_розмір", А.ширина_й_розмір(речі))):
            for з in знахідки:
                вих.append([назва, функція, з["правило"], з.get("суть"), з.get("речі"), з.get("сила"),
                            з.get("блокує"), відсів, з.get("сила_нп"),
                            обмежити_вагу([dict(з)])[0].get("сила_нп")])
                підсумок[з["правило"], з.get("сила")] += 1
    with gzip.open(sys.argv[1], 'wt', encoding='utf-8') as ф:
        json.dump(вих, ф, ensure_ascii=False)
    print('знахідок', len(вих), 'правил', sorted(підсумок.items()))


if __name__ == '__main__':
    main()
