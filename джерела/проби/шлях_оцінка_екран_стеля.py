"""Л-6: ФОТО ЇЇ ОБРАЗУ МУСЯТЬ ВЛІЗТИ В СТЕЛЮ МОСТУ разом із base64 (ділянка 5/8 — HTTP 413).
Міст рахує весь `messages` (worker.js `СТЕЛЯ_ВХОДУ_СИМВ`); збережений кадр (`блобВБазу`) — боком
`МАКС_СТОРОНА_П`. Оцінка шле фото тим самим шляхом, що кожен виклик (наряд Л-2): копія боком
`СТОРОНА_ФОТО_РЕЧІ_П` (`фотоДляЗапитуП`), стелю тримає `вмістити_запит_П` у `модельП`. Розмір кадру
на боці — вимір Л-2 у Chromium (`проби/шлях_розмір_фото_сторона.py`, ВИМІР). Проба рахує справжній
промпт відповіді й запит на 1…ОЦ_ФОТО_МАКС фото: ДО (збережені кадри) і ПІСЛЯ (копії під задачу).
Запуск із `джерела`: python3 проби/шлях_оцінка_екран_стеля.py"""
import sys, re, json; sys.path.insert(0, '.')
import оцінка_образу as О
exec(open('проби/шлях_оцінка_екран_образ.py', encoding='utf-8').read().split('for назва, екран')[0].split('"""', 2)[2])
показ = open('показ.html', encoding='utf-8').read()
число = lambda т, ім: int(re.search(ім + r"\s*=\s*(\d+)", т).group(1))
стеля = число(open('worker.js', encoding='utf-8').read(), "СТЕЛЯ_ВХОДУ_СИМВ")
межа = число(показ, "СТЕЛЯ_ЗАПИТУ_П") - число(показ, "ЗАПАС_ЗАПИТУ_П")
кадр, бік, n_макс = число(показ, "МАКС_СТОРОНА_П"), число(показ, "СТОРОНА_ФОТО_РЕЧІ_П"), число(показ, "ОЦ_ФОТО_МАКС")
ВИМІР = eval(re.search(r"ВИМІР = (\{.*?\})\n", open('проби/шлях_розмір_фото_сторона.py', encoding='utf-8').read()).group(1))
виклик = re.search(r"async function викликОцінкиП\(.*?\n\}\n", показ, re.S).group(0)
спільний = "фотоДляЗапитуП(фото, СТОРОНА_ФОТО_РЕЧІ_П)" in виклик and bool(re.search(r"модельП\([^)]*вміщ\)", виклик))
власна = bool(re.search(r"СТЕЛЯ_МОСТУ_СИМВ_П|фотоВСтелюП", показ))
print("стеля моста %d, межа коду %d; збережений кадр %d px, копія під задачу %d px; фото на образ до %d"
      % (стеля, межа, кадр, бік, n_макс))
print("оцінка шле фото спільним шляхом Л-2: %s; окрема стеля оцінки в показі: %s" % (спільний, власна))
с = О.суд(dict(вх, речі=речі, сценарій_оцінки={}, крамниця=False))
п = len(json.dumps(О.промпт_оцінки(с, {"free_text": "чи поєднуються ці кольори між собою?", "lang": "uk"}), ensure_ascii=False))
print("промпт відповіді %d симв. рядком JSON (так його бачить міст у `messages`)" % п)
вердикт = lambda а, б: "влазить" if б <= стеля else ("413" if а > стеля else "може 413")
for n in range(1, n_макс + 1):
    (дн, дв), (пн, пв), с_ = ВИМІР[кадр], ВИМІР[бік], бік
    while п + n * ВИМІР[с_][1] > межа and с_ > min(ВИМІР):   # `вмістити_запит_П`: сходинками вниз
        с_ = max(к for к in ВИМІР if к < с_)
    print("  %d фото: ДО %6d…%6d (%s) · ПІСЛЯ %6d…%6d (%s)%s" % (n, п + n * дн, п + n * дв, вердикт(п + n * дн, п + n * дв),
          п + n * пн, п + n * пв, вердикт(п + n * пн, п + n * пв),
          "" if с_ == бік else " → вмістити_запит_П до %d px: ≤ %d" % (с_, п + n * ВИМІР[с_][1])))
    assert п + n * ВИМІР[с_][1] <= межа, "після сходинок запит мусить влізти в межу коду"
assert спільний and not власна, "оцінка мусить іти спільним шляхом Л-2, без другої стелі"
