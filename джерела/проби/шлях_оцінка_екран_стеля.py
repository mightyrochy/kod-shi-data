"""Л-6: ФОТО ЇЇ ОБРАЗУ МУСЯТЬ ВЛІЗТИ В СТЕЛЮ МОСТУ разом із base64 (наряд Л-6, ділянка 5/8 — 413).
Міст рахує весь `messages` (worker.js `СТЕЛЯ_ВХОДУ_СИМВ`), фото після `блобВБазу` важить до
`МАКС_СИМВОЛІВ_ФОТО`. Екран оцінки стискає фото під бюджет (стеля − промпт − запас) / n
(`показ.html: фотоВСтелюП`). Проба рахує справжній промпт відповіді й бюджет на 1…6 фото.
Запуск із `джерела`: python3 проби/шлях_оцінка_екран_стеля.py"""
import sys, re, json; sys.path.insert(0, '.')
import оцінка_образу as О
exec(open('проби/шлях_оцінка_екран_образ.py', encoding='utf-8').read().split('for назва, екран')[0].split('"""', 2)[2])
показ = open('показ.html', encoding='utf-8').read()
воркер = open('worker.js', encoding='utf-8').read()
число = lambda т, ім: int(re.search(ім + r"\s*=\s*(\d+)", т).group(1))
стеля, фото_макс = число(воркер, "СТЕЛЯ_ВХОДУ_СИМВ"), число(показ, "МАКС_СИМВОЛІВ_ФОТО")
стеля_п, запас, n_макс = число(показ, "СТЕЛЯ_МОСТУ_СИМВ_П"), число(показ, "ЗАПАС_МОСТУ_П"), число(показ, "ОЦ_ФОТО_МАКС")
print("стеля мосту %d (у показі %d — %s); фото до %d симв.; запас %d; фото на образ до %d" % (
      стеля, стеля_п, "те саме" if стеля == стеля_п else "РОЗІЙШЛИСЬ", фото_макс, запас, n_макс))
с = О.суд(dict(вх, речі=речі, сценарій_оцінки={}, крамниця=False))
# промпт міряється рядком JSON — так, як його бачить міст у `messages` (лапки стають «\"»)
рядком = lambda т: len(json.dumps(т, ensure_ascii=False))
п_речі = рядком(О.промпт_речей([dict(ід="ф%d" % i, ширина=900, висота=1200) for i in range(1, n_макс + 1)]))
п_оц = рядком(О.промпт_оцінки(с, {"free_text": "чи поєднуються ці кольори між собою?", "lang": "uk"}))
print("промпт речей %d симв.; промпт відповіді %d симв. у `messages` (5 речей, 7 знахідок)" % (п_речі, п_оц))
for n in range(1, n_макс + 1):
    бюджет = (стеля_п - п_оц - запас) // n
    без = n * фото_макс + п_оц
    print("  %d фото: без стиснення до %7d симв. (%s); бюджет на фото %6d → разом ≤ %d" % (
          n, без, "413" if без > стеля else "влазить", бюджет, n * бюджет + п_оц + запас))
print("→ без бюджету 413 уже з двох фото; з бюджетом разом ≤ стелі на кожному n (фото стискаються")
print("  1280→512 px, якість 0.8→0.5; що не влізло — у етапах «стиснення», а не мовчанням).")
