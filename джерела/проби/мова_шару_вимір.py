"""Мовний шар на збережених текстах: ДО → ПІСЛЯ кожного тексту, скільки шар змінив, скільки
лишилось без відповіді й скільки тривав виклик. Змісту код не судить (власник 25.09: «Всі
інші костилі не потрібні») — точність читає людина з цього друку. Без MODEL — лише «до».
Запуск: cd джерела && MODEL=mamaylm-gemma-3-12b-it-v2.0 [MODEL_URL=…] \\
          python3 проби/мова_шару_вимір.py [тексти.json | тека VIDPOVIDI стенда]"""
import collections, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import мова_спільне as С
лік, секунд = collections.Counter(), 0.0
for г in С.групи(sys.argv[1] if len(sys.argv) > 1 else None):
    р, п, с = С.прогнати(г)
    секунд += с
    print("── %s%s" % (г["де"], " · %.1f с" % с if п else ""))
    for ч in р:
        лік["текстів"] += 1
        print("   ДО     %s" % ч["текст"])
        if not п:
            continue
        стало = п["тексти"][ч["ключ"]]
        без = ч["ключ"] in п["без_відповіді"]
        лік["без відповіді" if без else "змінено" if стало != ч["текст"] else "без змін"] += 1
        print("   ПІСЛЯ  %s%s" % (стало, "   [без відповіді: %s]" % п["причина"] if без else ""))
print("\nМОДЕЛЬ ШАРУ: %s · %s" % (С.МОДЕЛЬ or "нема (лише «до»)", С.АДРЕСА if С.МОДЕЛЬ else "—"))
print("ПІДСУМОК: " + " · ".join("%s %d" % кв for кв in лік.items())
      + (" · викликів %.0f с" % секунд if С.МОДЕЛЬ else ""))
