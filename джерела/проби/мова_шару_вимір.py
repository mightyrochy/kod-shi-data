# -*- coding: utf-8 -*-
"""Мовний шар на збережених текстах: ДО → ПІСЛЯ кожного тексту, скільки шар змінив, скільки
механічна перевірка відхилила й чому. Без MODEL — лише «до»: що в текстах бачить код.
Запуск: cd джерела && MODEL=mamaylm-gemma-3-12b-it-v2.0 [MODEL_URL=…] \\
          python3 проби/мова_шару_вимір.py [тексти.json | тека VIDPOVIDI стенда]"""
import collections, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import мова_спільне as С
лік, причини, секунд = collections.Counter(), collections.Counter(), 0.0
видно = lambda т: [з["фрагмент"] for з in С.М._МГ.російське(т) + С.М.на_ви(т)]
for г in С.групи(sys.argv[1] if len(sys.argv) > 1 else None):
    р, п, с = С.прогнати(г)
    секунд += с
    print("── %s%s" % (г["де"], " · %.1f с" % с if п else ""))
    за_ключем = {з["ключ"]: з for з in (п or {}).get("записи", [])}
    for ч in р:
        лік["текстів"] += 1
        до = видно(ч["текст"])
        лік["до: російська або «ви»"] += bool(до)
        print("   ДО     %s%s" % (ч["текст"], "   ← " + ", ".join(до) if до else ""))
        з = за_ключем.get(ч["ключ"])
        if not з:
            continue
        лік[з["рішення"]] += 1
        лік["після: російська або «ви»"] += bool(видно(з["стало"]))
        print("   ПІСЛЯ  %s   [%s]" % (з["стало"], з["рішення"]))
        for пр in з.get("причини") or []:
            причини[пр.split("«")[0].strip()] += 1
            print("          ✗ %s" % пр)
        if з.get("причини") and з.get("модель_написала"):
            print("          модель написала: %s" % з["модель_написала"])
print("\nМОДЕЛЬ ШАРУ: %s · %s" % (С.МОДЕЛЬ or "нема (лише «до»)", С.АДРЕСА if С.МОДЕЛЬ else "—"))
print("ПІДСУМОК: " + " · ".join("%s %d" % кв for кв in лік.items())
      + (" · викликів %.0f с" % секунд if С.МОДЕЛЬ else ""))
print("ПРИЧИНИ ВІДХИЛЕННЯ: " + ("; ".join("%s ×%d" % кв for кв in причини.most_common()) or "—"))
