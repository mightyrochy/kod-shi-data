# -*- coding: utf-8 -*-
# Реєстр проблем бази одягу, напрям В, клас «назва речі». ФАКТ на чистому каталозі (назва,
# яку бачить жінка й модель, — `фід_слот.назва_для_людини`): (1) назва російською чи лише
# латиницею; (2) розмір і колір у дужках у кінці назви («(3, XS, blue, синій)»); (3) назва-
# речення (> 10 слів) і назва, взята з опису (`назва_джерело=опис`); (4) назва, що не називає
# предмета (`фід_слот.предмет_назви` мовчить). Слова тут читає ПРОБА, не код продукту.
import os, re, sys, collections as C
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed, фід_слот as ФС
оф = feed.читати_yml(sys.argv[1] if len(sys.argv) > 1 else feed.каталог_на_диску())[0]
наз = [(o, ФС.назва_для_людини(o)) for o in оф]
РОС = re.compile(r"[ыэъё]|\b(платье|юбка|брюки|женск\w*|рубашка|кофта|туфли|сапоги|нарядн\w*)\b", re.I)
лат = [o for o, н in наз if not re.search("[а-яіїєґ]", н, re.I)]
рос = [o for o, н in наз if РОС.search(н)]
print("назв %d · російською %d %s · лише латиницею %d %s"
      % (len(наз), len(рос), dict(C.Counter(o["магазин"] for o in рос).most_common(4)),
         len(лат), dict(C.Counter(o["магазин"] for o in лат).most_common(4))))
дуж = [o for o, н in наз if re.search(r"\([^)]*\b(XS|S|M|L|XL|XXL|\d{1,2})\b[^)]*\)\s*$", н)]
print("розмір/колір у дужках у кінці: %d %s" % (len(дуж), dict(C.Counter(o["магазин"] for o in дуж).most_common(3))))
print("назва-речення (> 10 слів): %d · назва з опису: %d"
      % (sum(1 for _, н in наз if len(н.split()) > 10),
         sum(1 for o in оф if ((o.get("параметри") or {}).get("назва_джерело") or "") == "опис")))
без = [н for o, н in наз if not ФС.предмет_назви(н.lower())]
print("назва без предмета: %d, напр. %s" % (len(без), [н[:40] for н in без[:4]]))
