"""Вкладка «Усі образи» малює заглушку замість згенерованої картинки образу.

Мініатюру бібліотека бере з ПЕРШОГО знімка крамниці (`x.фото`), а приміряний
кадр (`карт.картинка`, який показ уже кладе в сховище «образи») не читає зовсім;
падіння знімка вона теж не переживає — на картці кадр перебирається двома колами
(`підставитиКадр`), у бібліотеці стоїть голий <img> без `onerror`.
"""
import json
import pathlib

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
ПОКАЗ = (КОРІНЬ / "джерела" / "показ.html").read_text(encoding="utf-8")
рядки = ПОКАЗ.splitlines()

поч = next(i for i, р in enumerate(рядки) if "async function оновитиБібліотеку" in р)
кін = next(i for i, р in enumerate(рядки) if "function відкрити(о, i)" in р)
блок = "\n".join(рядки[поч:кін])
for i in range(поч, кін):
    if "x.фото" in рядки[i] or "арка" in рядки[i]:
        print("показ.html:%d" % (i + 1), рядки[i].strip()[:130])
print("у блоці бібліотеки (%d рядків): «картинка» %d · «підставитиКадр» %d · «onerror» %d · «фото_усі» %d"
      % (кін - поч, блок.count("картинка"), блок.count("підставитиКадр"),
         блок.count("onerror"), блок.count("фото_усі")))
print("на картці ж: «підставитиКадр» у показі всього", ПОКАЗ.count("підставитиКадр"),
      "· друге коло перебору кадрів:", ПОКАЗ.count("коло = 1"))

ф = КОРІНЬ / "аудит" / "тести" / "власник_2026-09-25" / "verdykty-0phxvk-2026-09-25-2012.json"
д = json.loads(ф.read_text(encoding="utf-8"))
з_кадром = 0
for п in д["прогони"]:
    for в in п["вердикти"]:
        к = в.get("примірка_картинка")
        if к:
            з_кадром += 1
            print("розклад", п["спільне"].get("розклад"), "· рука", в.get("рука"),
                  "· приміряний кадр є:", к["ширина"], "×", к["висота"], "px,",
                  round(к["символів"] / 1024), "КБ — у «Усі образи» він не показується")
print("вердиктів із готовим приміряним кадром:", з_кадром, "з", д["вердиктів"])
