"""Реєстр проблем каталогу, напрям Б, клас Б6: колір речі досі вирішує код, що читає слова кольору (п.12; 5190, 5204, 5333).
ФАКТ — скільки записів отримали колір або його вікно через розбір слова кодом (`verify.слово_крамниці`): слово стало
назвою й вікном, слово «не колір» чи «лексикон не знає» віддало колір фото, слова нема; і скільки різних написів поля
«Колір» мусить колись перекласти мовна модель. Запуск: cd джерела && python3 -W ignore проби/каталог_проблеми_б_слово.py"""
import collections, gzip, os, re, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as FK
К = FK._прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"]
ч = lambda r: r.get("колір_назва_за_чим") or ""
сл_вікно = sum(r.get("колір_назва_джерело") == "крамниця" for r in К)
лише_сл = sum(r.get("колір_джерело") == "назва_вікно" for r in К)
не_колір = collections.Counter(re.search(r"не колір \(([^)]*)\)", ч(r)).group(1) for r in К if "не колір (" in ч(r))
не_знає = sum("лексикон не знає" in ч(r) for r in К)
нема = sum("не дала" in ч(r) for r in К)
print("ФАКТ · записів %d; назву й вікно кольору дало слово крамниці, розібране кодом: %d (%.1f %%); з них колір лише зі "
      "слова, без виміру: %d" % (len(К), сл_вікно + лише_сл, 100 * (сл_вікно + лише_сл) / len(К), лише_сл))
print("ФАКТ · код визнав слово «не колір»: %d %s; «лексикон не знає»: %d; слова кольору крамниця не дала: %d" % (
    sum(не_колір.values()), dict(не_колір.most_common()), не_знає, нема))
xml = gzip.open(os.path.join(ТУТ, "..", "каталог_повний.xml.gz")).read().decode()
поле = re.findall(r'<param name="~?[Кк]олір">([^<]*)</param>', xml)
print("ФАКТ · сирий XML: входжень «Колір»/«~Колір» %d, різних написів %d; з комою (перелік варіантів) %d" % (
    len(поле), len(set(поле)), sum("," in п for п in поле)))
