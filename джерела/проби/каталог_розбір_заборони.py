"""Проба К-5: ЗАБОРОНИ рядка `features` на збережених відповідях прогону — друкує факт, моделі не кличе. Менеджер 27.09
переглянув 20 рядків очима й назвав, що прибрати: маркетинг і оцінки, розмір і обміри, бренд і назву моделі, назву
кольору (колір несе код; виняток — кольори візерунка), країну; РЗ-1 додав догляд і відгук покупця з правила §3
«Ноутбук». СКЛАД ТКАНИНИ ЛИШАЄТЬСЯ — проба міряє його окремо, щоб було видно, що заборони не з'їли й його.
КРИТЕРІЙ ТУТ НЕ СВІЙ: і проба, і крок `--підставити` беруть `каталог_розбір_прогін.заборони_рядка`, інакше
«чисто» для виміру й «чисто» для повтору розійшлись би. «До/після» правила — та сама проба на двох теках поруч.
Запуск: python3 джерела/проби/каталог_розбір_заборони.py [тека …]"""
import glob, json, os, sys, tarfile  # noqa: E401
Д = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, Д)  # noqa: E702
import каталог_розбір as КР, каталог_розбір_прогін as П  # noqa: E401,E402
for т in sys.argv[1:] or sorted(glob.glob(os.path.join(Д, "..", "аудит", "розбір_каталогу", "*_uk*"))):
    м = json.load(open(os.path.join(т, "прогін.json"), encoding="utf-8")); тар = os.path.join(т, "сирі_відповіді.tar.gz")  # noqa: E702
    сирі = {ч.name: а.extractfile(ч).read().decode("utf-8") for а in ([tarfile.open(тар)] if os.path.exists(тар) else []) for ч in а if ч.isfile()}  # noqa: E501
    рядків, влип, склад, чистих = 0, {і: [] for і in П.ЗАБОРОНИ}, 0, 0
    for р in м["речі"]:
        ф = os.path.join(т, р["файл"])
        цілий = open(ф, encoding="utf-8").read() if os.path.exists(ф) else сирі.get(р["файл"], "")
        дані, відп = П.розділити(цілий)
        поля = КР.з_відповіді(відп)[0]
        if not поля or поля[КР.ОСОБЛИВОСТІ] == КР.UNKNOWN: continue  # noqa: E701
        f = поля[КР.ОСОБЛИВОСТІ]; рядків += 1; склад += bool(П.СКЛАД_ТКАНИНИ.search(f))  # noqa: E702
        збіги = П.заборони_рядка(f, дані, р["id"])
        чистих += not збіги
        for і, з in збіги:
            влип[і].append("%s: …%s…" % (р["id"], f[max(0, f.find(з) - 18):f.find(з) + len(з) + 18].strip()))
    print("%s · рядків (не unknown) %d · чистих %d (%d %%) · склад тканини в %d (%d %%)"
          % (os.path.basename(os.path.normpath(т)), рядків, чистих, round(100.0 * чистих / max(рядків, 1)),
             склад, round(100.0 * склад / max(рядків, 1))))
    for і in П.ЗАБОРОНИ:
        print("  %-10s %4d (%2d %%)%s" % (і, len(влип[і]), round(100.0 * len(влип[і]) / max(рядків, 1)),
                                          "".join("\n      " + п for п in влип[і][:3])))
