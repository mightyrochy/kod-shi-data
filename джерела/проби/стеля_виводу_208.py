# -*- coding: utf-8 -*-
"""Рядок 208 · скільки виводу треба кожному кроку, коли модель відповідає РІВНО тією формою, яку
просить промпт (ПАКЕТ 10 образів, ремонт 5 із «виконано», ВИБІР, ОПИС), — на справжньому пулі
стенда (`стенд_вх.json`, каталог_повний). TOKENIZER=<tokenizer.json> — лічба токенів ним; без
нього — символи й міра тестувальниці 24.09 (qwen3.5: 9 324 симв. = 4 000 т.). Друкує факт.
Запуск: cd джерела && [TOKENIZER=…] python3 проби/стеля_виводу_208.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, протокол as P
т_ = os.environ.get("TOKENIZER")
лічба = (lambda т: len(__import__("tokenizers").Tokenizer.from_file(т_).encode(т).ids)) if т_ else \
        (lambda т: round(len(т) / (9324 / 4000)))
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), варіантів=10, ремонт_варіантів=5,
          бюджет_символів=120000, без_фото=1)
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
пул = json.loads(r["руки"]["1"])["пул"]; н = lambda с, k: пул[с][k % len(пул[с])]["н"]
ДЕНЬ = "Цілий день в офісі за столом і коротка дорога містом: тканина не мнеться, лофери не натирають."
образи = [dict(ід="о%d" % (і + 1), підпис="тихий беж із хакі", полюс=P.ПОЛЮСИ[і % 6], день=ДЕНЬ,
               речі=([н("сукня", і)] if і % 2 else [н("верх", і), н("низ", і)]) + [н(с, і) for с in ("взуття", "сумка", "прикраси", "пояс")],
               **({"свідомо": [dict(річ=н("взуття", і), чому="узято навмисно: теплий акцент, решта спокійна")]} if і % 3 == 0 else {}))
          for і in range(10)]
в = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=json.dumps(dict(версія="1", образи=образи), ensure_ascii=False)), ensure_ascii=False)))
пр = json.loads(в["промпт_ремонту"])   # Т-7: суд на дроті — «вердикт»[].твій_образ; main — «образи»
вд = [dict(с["твій_образ"], знахідки=с.get("знахідки")) if "твій_образ" in с else с for с in (пр.get("вердикт") or пр["образи"])][:5]
рем = lambda усі: [dict(ід=о["ід"], речі=о["речі"], день=ДЕНЬ, виконано=[dict(знахідка=з["ід"], дія="частково", чому="лишила як є: це задум образу")
                   for з in (о.get("знахідки") or []) if усі or з.get("регістр") == "гейт"]) for о in вд]
ОП = ("Сукня міді з віскози, пряма, пісочна.\nЛофери шкіряні, темно-коричневі.\nСумка через плече, коньячна.\n"
      "Пояс вузький.\nСережки дрібні, золотисті.\nВзуття й сумка в одному теплому тоні тримають образ зібраним. " * 2)
for ім, об in (("ПАКЕТ → ОБРАЗИ (10 образів)", dict(версія="1", образи=образи)),
               ("ремонт → ОБРАЗИ, «виконано» на гейти", dict(версія="1", образи=рем(False))),
               ("ремонт → ОБРАЗИ, «виконано» на всі", dict(версія="1", образи=рем(True))),
               ("ВИБІР", dict(версія="1", обрано="о3", чому="Тримає діловий тон і витримає день.", прибрати=[])),
               ("ОПИС", dict(версія="1", текст=ОП, як_носити=["Пояс — на талії.", "Сумку — через плече."], фото_не_те=[]))):
    for вид, т in (("стисло", json.dumps(об, ensure_ascii=False)), ("з відступами", json.dumps(об, ensure_ascii=False, indent=2))):
        print("%-38s %-12s симв %5d · %s %4d" % (ім, вид, len(т), "токенів" if т_ else "≈т. (qwen3.5)", лічба(т)))
print("стеля показу й мосту: 4000 т. · промпт ВИБОРУ (ехо переписувало б його): %d симв." % len(в["промпт_лише_вибору"]))
