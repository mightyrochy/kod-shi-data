# -*- coding: utf-8 -*-
"""Розбір шляху 4/8 · «слот_двічі» і ремонт повноти. Відповідь ремонту: 5 образів, у кожному двоє взуття (решта
слотів є) — і для порівняння ті самі образи без сумки. Друкує: блокери структури, чи будує код промпт повноти,
що `повнота` віддає на картку, і що робить добір кодом на останній спробі (`спроба_повноти` = стеля реєстру).
Запуск: cd джерела && python3 проби/шлях_виклики_слот_двічі.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, реєстр_правил as Р, суд_від_моделі as С
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), варіантів=10, ремонт_варіантів=5, бюджет_символів=120000, без_фото=1)
пул = json.loads(json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["руки"]["1"])["пул"]
н = lambda с, k: пул[с][k % len(пул[с])]["н"]
повні = lambda k: [н("верх", k), н("низ", k), н("взуття", k), н("сумка", k), н("пояс", k)]
від = lambda т, **д: json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=т, **д), ensure_ascii=False)))
відп = lambda f: json.dumps(dict(версія="1", образи=[dict(ід="о%d" % (і + 1), підпис="беж", день="Офіс.", речі=f(і)) for і in range(5)]), ensure_ascii=False)
в1 = від(відп(повні))
print("СЛОТИ_БЛОКЕРА (що лікує ремонт повноти): %s" % sorted(С.СЛОТИ_БЛОКЕРА))
for ім, f in (("два взуття", lambda k: повні(k) + [н("взуття", k + 7)]), ("без сумки", lambda k: повні(k)[:3] + повні(k)[4:])):
    for сп in (0, Р.C["спроб_повноти"]):
        в2 = від(відп(f), ітерація=2, попередній_вердикт=в1["вердикт"], **({"спроба_повноти": сп} if сп else {}))
        пв = в2.get("повнота") or {}
        бо = [{б.get("код") for б in ((о.get("структура") or {}).get("блокери") or [])} for о in (в2["вердикт"].get("образи") or [])]
        бл = sorted(set().union(*бо)) + ["у %d з %d образів" % (sum(bool(x) for x in бо), len(бо))]
        print("%-10s · спроба %d → блокери %s · промпт повноти %d симв. · на картку ід %d, повний %s, код дібрав %s, код зняв %s"
              % (ім, сп, бл, len(в2.get("промпт_повноти") or ""), len(пв.get("ід") or []), пв.get("повний"),
                 [д.get("слот") for д in (пв.get("дібрані") or [])] or "—", [x.get("слот") for x in ((пв.get("ремонт_гейтів") or {}).get("взято") or [])] or "—"))
        if not пв.get("повний"): print("   жінці: %s" % пв.get("рядок"))
        if сп == 0 and "слот_двічі" in бл:
            в3 = від(json.dumps(dict(версія="1", обрано="о1", чому="так", прибрати=[])), ітерація=2, відповідь="ВИБІР_V1", вибір_над=в2["вибір_над"])
            вб = в3.get("вибір") or {}
            print("   вибір «о1» → ід %d, замінено %s · %s" % (len(вб.get("ід") or []), вб.get("замінено"), str(вб.get("чому_відмова") or "прийнято")[:150]))
