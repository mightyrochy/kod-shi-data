# -*- coding: utf-8 -*-
"""K-EDG-01 / K-ACC-04 (край аксесуара сідає на опуклість) — поле дістало постачальника.

ДО ПРАВКИ: `accessory.НОСІЇ_КРАЮ` читає `ремінь_см`, і не писав його НІХТО в усьому
дереві. Реєстр `БЕЗ_ВХОДУ["K-ACC-04"]` це чесно називав: «на 476 сумках довжина
ременя парситься 0 разів». Отже єдине правило про посадку сумки на корпусі не
виконувалось жодного разу.
ПІСЛЯ: `feed.аксесуарні_довжини` читає ручку з картки (177 із 476 сумок каталогу,
37.2 %) і віддає ПАДІННЯ = половина довжини петлі. У пакеті 141 сумка несе
`ремінь_см`; K-EDG-01 спрацьовує на 11 із них, решта 130 проходять правило й
мовчать законно."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, accessory as АК, fit as ПС

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
T = ПС.тіло(float(вх["зріст"]), {k: float(v) for k, v in вх["обхвати"].items()})
сумки = [c for c in кат if c.get("ремінь_см") is not None]
спрац = [c for c in сумки if АК.край_аксесуара(T, [dict(c)])]
print("сумок у пакеті %d · із них несуть ремінь_см %d · край сідає на опуклість %d"
      % (sum(1 for c in кат if c.get("слот") == "сумка"), len(сумки), len(спрац)))
с = спрац[0]
print("   «%s» падіння %.1f см · %s" % (с["назва"][:40], с["ремінь_см"], с["ремінь_джерело"]))
база = [next(c for c in кат if c.get("слот") == сл) for сл in ("сукня", "взуття")]
вм = json.loads(B.виклик("від_моделі", json.dumps(
    dict(вх, ід=[c["id"] for c in база] + [с["id"]]), ensure_ascii=False)))
о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
р = next((z for z in (о.get("знахідки") or []) if z.get("правило") == "K-EDG-01"), None)
print("K-EDG-01 у вердикті:", "НЕМА" if not р else
      "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:62]))
print("ремонт називає, куди зсунути:", str((р or {}).get("ремонт"))[:78])
assert р, "край аксесуара мусить доїжджати у вердикт"
assert len(спрац) and len(спрац) < len(сумки), "правило мусить і спрацьовувати, і мовчати"
