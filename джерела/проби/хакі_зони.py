# -*- coding: utf-8 -*-
"""Х-1 «хакі»: звідки межі вікна. Одиниця — ДИЗАЙН: поле кольору з одного слова й вимір з фото (hex жнив v2, підтверджений
свідком), каталог_повний. Друкує: які слова крамниць лежать у зонах, що нове вікно бере або лишає; і для чотирьох вікон
«хакі» — скількох дизайнів підпис точки (`palettes._назва`: найтісніше вікно) збігається зі словом крамниці, скільки
дизайнів «хакі» підписано «хакі», і що стає з ґраткою основ (м'ятні клітинки). Запуск: cd джерела && python3 проби/хакі_зони.py"""
import collections as К, statistics as st, sys
sys.path.insert(0, ".")
import feed, міст_основи as МО, palettes as PS, фід_каталог as FK, фід_збагачення as FZ, фід_розбір as FR, verify as V, colorspace as cs
зб, н, гр = feed.читати_збагачення(), lambda s: " ".join(str(s or "").lower().split()), К.defaultdict(list)
for o in FR.читати_yml("каталог_повний.xml")[0]:
    п, z = н(o.get("колір_сирий")), зб.get(o["id"]) or {}
    if not п or len(FK._СЕП_КОЛЬОРУ.split(п)) > 1 or not (z.get("колір_основний") or {}).get("hex") or (z.get("версія") or 1) < 2: continue
    ск = FZ.колір_збагачення(z)[2].startswith("hex") and V.слово_крамниці(п)
    if ск: гр[(ск["ім"], z.get("фото") or o.get("group_id") or o["id"])].append(cs.hx(z["колір_основний"]["hex"]))
Д = [(с, tuple(st.median(x[i] for x in v) for i in range(3))) for (с, _), v in гр.items()]
def зона(Ll, Lh, Cl, Ch, a, b):
    c = К.Counter(с for с, l in Д if (lambda L, C, h: Ll <= L < Lh and Cl <= C < Ch and a <= h < b)(*cs.lch(l)))
    return "%d дизайнів, з них «хакі» %d; найчастіші %s" % (sum(c.values()), c["хакі"], c.most_common(3))
print("ФАКТ · темна олива L*23–35, C*10–28, тон 85–130° (нове вікно бере): %s" % зона(23, 35, 10, 28, 85, 130))
print("ФАКТ · смуга C*8–10, L*35–70, тон 85–130° (нове вікно лишає): %s" % зона(35, 70, 8, 10, 85, 130))
print("ФАКТ · смуга C*28–32, L*35–70, тон 85–130° (нове вікно лишає): %s" % зона(35, 70, 28, 32, 85, 130))
print("ФАКТ · тон 59–85°, L*23–70, C*10–28 (дуга від 85° лишає): %s" % зона(23, 70, 10, 28, 59, 85))
W, Д_ = V.ЛЕКСИКОН["хакі"], [(с, l) for с, l in Д if с not in V.ВІКНА_КРАМНИЦЬ]
def стан(w):
    V.ЛЕКСИКОН["хакі"] = w; МО._ҐРАТКА_КЕШ.clear()
    осн, пор = МО._ґратка_основ(); МО._ҐРАТКА_КЕШ.clear()
    підп = [PS._назва(l, виключити=V.МЕТАЛИ)[0] for _, l in Д_]
    return dict(осн), list(пор), sum(с == п for (с, _), п in zip(Д_, підп)), sum(с == п == "хакі" for (с, _), п in zip(Д_, підп)), підп.count("хакі")
try:
    б = стан((35, 70, 8, 32, (85, 130)))
    for ім, w in (("було", (35, 70, 8, 32, (85, 130))), ("чинне", W), ("перцентильне", (10, 65, 3, 31, (59, 113))), ("дуга від 59°", (W[0], W[1], W[2], W[3], (59, W[4][1])))):
        с = стан(w); зм = [к for к in set(б[0]) | set(с[0]) if б[0].get(к) != с[0].get(к)]
        print("ФАКТ · %-13s %-27s підпис = слово крамниці: %d із %d; «хакі» підписано «хакі» %d із %d; «хакі» підписує %d дизайнів; ґратка %s, м'ятних змінено %d" % (
              ім, w, с[2], len(Д_), с[3], sum(с_ == "хакі" for с_, _ in Д_), с[4], "та сама" if с[:2] == б[:2] else "змінилась (%d клітинок)" % len(зм), sum(к.startswith("м'ятний") for к in зм)))
finally:
    V.ЛЕКСИКОН["хакі"] = W; МО._ҐРАТКА_КЕШ.clear()
