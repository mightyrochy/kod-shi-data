"""ПРИМ-1 (рядок 750): число смуги ошатності в `case` рук 3–4. Рядок випадку (`паспорт_рядком`) — єдиний опис
випадку рук 3–4 — несе «ошатність 7–8 з 10», а межа `без_чисел_тіла` забороняє моделі лише числа світлоти й
типи фігури: число смуги доходило до тексту жінки («вишуканий образ на 7–8 балів із 10»). Друкує рядок для
смуг стенда (співбесіда 7–8, театр 6–7, робота 5–6) і чи є в ньому число зі шкали. Запуск із `джерела`:
PYTHONPATH=. python3 проби/р34_смуга_в_тексті.py"""
import re, sys; sys.path.insert(0, ".")
import паспорт_нагоди as ПН
шкала = re.compile(r"\d\s*[–-]\s*\d|з 10|із 10|/ ?10")
for подія, смуга in (("співбесіда на посаду юриста в банку", [7, 8]), ("театр", [6, 7]), ("робота за таблицею", [5, 6])):
    п = {"подія": подія, "година": 10, "ошатність": смуга, "джерело_полів": {"ошатність": "слова"}}
    р = ПН.паспорт_рядком(п)
    print("смуга %-6s → число зі шкали в рядку: %-3s · %s" % (смуга, "так" if шкала.search(р) else "ні", р))
