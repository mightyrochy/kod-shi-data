"""Друкує відмови справжніх запитів моста на повному каталозі, без виклику моделі."""
import json
import os
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import bridge as Б

if __name__ == "__main__":
    os.chdir(sys.path[0])
    межі = ["підбори", "сукня"]
    вхід = dict(json.loads(Path("стенд_вх.json").read_text(encoding="utf-8")),
                жорстке_ні=межі, межі=межі, без_фото=1, варіантів=10, ремонт_варіантів=5)
    def міст(імʼя, **поля):
        """Викликає міст із тим самим входом і перевіряє його помилку."""
        вихід = json.loads(Б.виклик(імʼя, json.dumps(dict(вхід, **поля), ensure_ascii=False)))
        assert not вихід.get("помилка"), вихід
        return вихід

    def показати(назва, текст, треба=True):
        """Показує поле відмов і перевіряє його канонічні значення."""
        дріт = json.loads(текст)
        значення = дріт.get("she_refuses")
        print(назва, "she_refuses=", значення, flush=True)
        assert not треба or значення == ["heels", "dress"], (назва, значення)

    запити = міст("запити")
    показати("складання", запити["B"])
    пул = запити["пакети"]["1"]["пул"]
    образи = [dict(ід="о%d" % (н + 1), речі=[пул[с][н % len(пул[с])]["н"]
                for с in ("верх", "низ", "взуття", "сумка")]) for н in range(4)]
    відповідь = міст("від_моделі", текст_моделі=json.dumps(dict(версія="1", образи=образи), ensure_ascii=False))
    for поле in ("промпт_ремонту", "промпт_лише_вибору", "промпт_повноти_до_вибору"):
        if відповідь.get(поле): показати(поле, відповідь[поле], поле != "промпт_ремонту")
    for спосіб in ("assess", "tournament"):
        оцінка = міст("від_моделі", вибір_речей={"спосіб": спосіб})
        показати(спосіб, оцінка["вибір_речей"]["запити"][0]["текст"])
    опис = міст("опис", речі=[запити["кандидати"][с][0]["id"] for с in ("верх", "низ", "взуття", "сумка")])
    показати("опис", опис["промпт"])
