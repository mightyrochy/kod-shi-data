"""Прилад запису сцени (`аудит/проби/записати_сцену.py`) бере змінні з полів «режим» і «вхід» реєстру `живі_сцени.txt`
(наряд проби-оцінка-за-режимом, #2578): повне → OTSINKA=0; «+фото» → FOTO=1; «(стенд: сцени 6 і 6б)» → без OTSINKA=0;
розмова/палітра/коментар/оцінка → DO; вхід дописує; «функція» і невідомий режим — відмова до старту. Друкує розбіжності.
Запуск: python3 джерела/проби/запис_сцени_режим.py"""
import importlib.util, pathlib
к = pathlib.Path(__file__).resolve().parents[2]
с = importlib.util.spec_from_file_location("запис", к / "аудит/проби/записати_сцену.py"); м = importlib.util.module_from_spec(с); с.loader.exec_module(м)
очікувано = {"ж1_оціни_образ_6б": {"FOTO": "1"}, "ж2_побачення_вечір": {"OTSINKA": "0", "FOTO": "0"}, "ж1_робота": {"OTSINKA": "0", "FOTO": "0"},
             "ж8_вище_офіс": {"DO": "rozmova", "FOTO": "0"}, "ж1_213_золоте_намисто": {"OTSINKA": "0", "FOTO": "1", "ODNOCHASNO": "1"}}
хиби = []
for id_, ож in очікувано.items():
    зм = м.сцена_реєстру(id_)["змінні"]
    хиби += [f"{id_}: {к_}={зм.get(к_)!r}, за реєстром {в!r}" for к_, в in ож.items() if зм.get(к_) != в]
    хиби += [f"{id_}: зайве {к_}={зм[к_]!r}" for к_ in ("OTSINKA", "DO") if к_ in зм and к_ not in ож]
for режим, вхід in (("функція", ""), ("щось нове", ""), ("палітра (стенд: сцени 6)", ""), ("повне", "ЗМІННА")):
    try: м.змінні_режиму("х", режим, вхід); хиби.append(f"«{режим}» {вхід!r} не відмовлено")
    except ValueError: pass
рядки = [р.split("|")[0] for р in (к / "аудит/проби/живі_сцени.txt").read_text(encoding="utf-8").splitlines() if р and р[0] != "#"]
відмов = []
for id_ in рядки:
    try: м.сцена_реєстру(id_)
    except ValueError as в: відмов.append(str(в))
хиби += [в for в in відмов if "«функція»" not in в]
print("сцен у реєстрі:", len(рядки), "· відмов (функція):", len(відмов), "· розбіжностей:", len(хиби)); [print(" ", х) for х in хиби]
raise SystemExit(1 if хиби else 0)
