"""РЕМОНТ-2 (рядки 967, 843, 966): записані прогони — образів на вибір (без блокера), речей на картці, порожня картка.
ДО — як записано; ПІСЛЯ — рішення коду над тими самими даними: 967 — відповідь ремонту розбирається наново; 843 — фінали
з дірою йдуть у ремонт повноти до вибору (`вердикт_повноти(всі=True)`). Запуск: cd джерела && python3 проби/ремонт2_повнота.py"""
import sys, os, json, gzip
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import протокол as П, розбір_відповідей as Р, повнота_образу as ПО
А = "../аудит/перевірки/"
рука = lambda ф, р: next(v for п in json.load(gzip.open(А + ф))["прогони"] for v in п["вердикти"] if str(v["рука"]) == р)
крок = lambda v, к: [x for x in v["етапи"]["виклики"] if x["крок"] == к]
двері = lambda о: sum(1 for x in о if not x.get("блокери"))
# 967 · ж2_модель_робота, рука 2: зламаний JSON ремонту
v = рука("zamir_sh_pislia/ж2_модель_робота/вердикти.txt.gz", "2")
рем, оп = крок(v, "repair")[0], крок(v, "description")[0]
об, _, нот = П.розбір_за_схемою(рем["відповідь_сира"], "ОБРАЗИ_V1")
print("967 ДО:    образів на вибір %d (речей %s) · completeness_repair ×%d · речей на картці %d · порожня: ні"
      % (len(рем["образи_кроку"]), [len(о["ід"]) for о in рем["образи_кроку"]], len(крок(v, "completeness_repair")),
         len(оп["повнота"]["ід"])))
print("967 ПІСЛЯ: образів на вибір %d (речей %s) · %s · злиток з тексту: %s"
      % (len(об["образи"]), [len(о["речі"]) for о in об["образи"]], "; ".join(нот["нормалізовано"]),
         "ні" if Р._зламаний_json_образів(рем["відповідь_сира"].replace("].slice", "]].slice"), "x") else "так"))
# 843 · vyb1/театр_В, рука 1: 4 з 5 фіналів без сумки
v = рука("vyb1/театр_В/вердикти.txt.gz", "1")
рем, вб = крок(v, "repair")[0], крок(v, "choice")[0]
образи = [dict(ід=о["номер"], підпис=о.get("підпис"), речі=о["речі_н"], структура=dict(ок=not о["блокери"], блокери=о["блокери"]))
          for о in рем["образи_кроку"]]
пвн = ПО.вердикт_повноти(dict(рем["вердикт_кроку"], образи=образи), спроба=1, всі=True)
закриває = [о["ід"] for о in пвн["образи"] if all(sum(1 for с in ПО.СЛОТИ_БЛОКЕРА.get(б["код"], ()) if пвн["вітрина"].get(с)) or б["код"] == "слот_двічі"
                                                  for б in о["структура"]["блокери"])]
print("843 ДО:    образів на вибір %d з %d · вибір: «%s…» · ремонту повноти до вибору нема"
      % (двері(рем["образи_кроку"]), len(образи), json.loads(вб["відповідь_сира"])["why"][:48]))
print("843 ПІСЛЯ: у ремонт повноти до вибору %d (%s) · вітрина: %s · образів на вибір до %d → після (якщо модель закриє) %d"
      % (len(пвн["образи"]), ",".join(о["ід"] for о in пвн["образи"]), {с: len(р) for с, р in пвн["вітрина"].items()},
         двері(рем["образи_кроку"]), двері(рем["образи_кроку"]) + len(закриває)))
# 966 · _збій1_ж1_контраст_побачення, рука 1: вибір прийнято, картка неповна (лише лог)
лог = gzip.open(А + "zamir_sh_pislia/_збій1_ж1_контраст_побачення/лог.txt.gz", "rt").read()
ряд = [л.strip() for л in лог.splitlines() if л.strip().startswith("· hand_1 ·")]
print("966 ДО:    вибір відхилено: %s · completeness_repair: %d · %s · речей на картці 0 · порожня: так"
      % ("так" if any("choice_not_complete" in р for р in ряд) else "ні", sum("completeness_repair" in р for р in ряд),
         next((р.split(" · why=")[0][2:] for р in ряд if "no_accepted_outfit" in р), "")))
