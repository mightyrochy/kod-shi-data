"""Власні виміри сегментів і невідомий колір на межі жнив, фіда та суду."""
import sys
sys.path.insert(0, ".")
import colorspace as КС, колір_річ as КР, outfit as О, фід_збагачення as ФЗ
from жнива_колір import звести_колір

перший = dict(слово="червоний", hex="#ee1111", lab=КС.hx("#ee1111"),
              частка=.7, колір_тип="вимір", тон=30)
другий = dict(слово="сірий", hex="#777777", lab=КС.hx("#777777"),
              частка=.3, колір_тип="невідомо", тон=None)
а, б, _ = звести_колір([перший, другий], "червоний", [])
for основний, другий_ in ((а, б), (dict(б, частка=.7), dict(а, частка=.3))):
    р = dict(id="поверхня", слот="верх")
    ФЗ.накласти_колір(р, dict(версія=2, колір_основний=основний, колір_другий=другий_))
    елементи = О.елементи([р])
    for сегмент, запис, елемент in zip((основний, другий_), (р, р["колір_другий"]), елементи):
        assert КР.тип_кольору(запис) == КР.тип_кольору(елемент) == сегмент["колір_тип"]
        if сегмент["колір_тип"] == "невідомо":
            assert КР.межі_кольору(запис) is КР.межі_кольору(елемент) is None
            assert КР.не_вимір(запис)["свідок"] == "невідомо"
        else:
            assert КС.de00(КР.точка_кольору(елемент), сегмент["lab"]) < 1
синій = КС.hx("#0000ff")
for батько in (dict(hex="#ff0000"), dict(колір_тип="невідомо"),
               dict(колір_тип="інтервал", колір_не_вимір=dict(свідок="shop_word", вікно=(0, 100, 0, 10, None)))):
    р = dict(батько, id="два", слот="верх", colors=[dict(lab=синій, coverage=1)])
    assert КР.точка_кольору(О.елементи([р])[0]) == синій
assert КР.lab_входу(dict(lab=синій, hex="#ff0000")) == синій
assert КР.lab_входу(dict(lab=синій, колір_джерело="назва_вікно")) is None
print("Обидва сегменти зберігають невідомо; вимір і походження сегмента незалежні від речі; Lab має перевагу над hex")
