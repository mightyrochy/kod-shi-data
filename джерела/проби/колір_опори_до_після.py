import json, gzip, random, sys, collections as K
sys.path.insert(0, "."); from суд_ремесло import ДУГА_ВІДЛУННЯ; import bridge as B, fit as ПС, colorspace as cs, pipeline as PL, стенд_знімок as СЗ
import колір_річ as КР, аксесуари_структура as АС, verify as V, фід_збагачення as ФЗ, колір_простір_риси as КП
вх0 = json.load(open("стенд_вх.json", encoding="utf-8")); зб = json.load(gzip.open("каталог_збагачення.json.gz"))
T = ПС.тіло(float(вх0["зріст"]), {k: float(v) for k, v in вх0["обхвати"].items()}); F = cs.features(cs.hx(вх0["шкіра"]), cs.hx(вх0["волосся"][0]), cs.hx(вх0["очі"]))
def в1(r):
    нв, з = КР.не_вимір(r), зб.get(r.get("id")) or {}
    if not нв or нв["свідок"] != "слово крамниці" or з.get("версія") != 2 or (r.get("колір_спір") or {}).get("чому") != "згода свідків нижча за поріг": return r
    lab = ФЗ._lab_з_hex((з.get("колір_основний") or {}).get("hex"))
    if not lab or нв["слово"] not in V.ЛЕКСИКОН or V.перевірити(lab, ім=нв["слово"])["вердикт"] != "прийнято": return r
    return {**{k: v for k, v in r.items() if k != "колір_не_вимір"}, "lab": tuple(lab)}
def на_колі(x):   # межі тону — на коло художника (монотонне на дузі), як `суд_від_моделі` (~447)
    м = КР.межі_кольору(x)
    return x if м is None or м[4] is None else dict(колір_не_вимір=dict(вікно=(*м[:4], tuple(КП.у_коло_художника(h) for h in м[4]))))
СЛОТИ = ("верх", "низ", "сукня", "верхній_шар", "взуття", "сумка", "шарф", "сережки", "намисто"); Л = K.Counter(); гучна = lambda x: (АС._C_речі(x) or 0.0) >= 40
for назва in ("офіс·18°C", "дощ·ресторан·вечір", "весілля·гість", "спека·парк"):
    сц = dict(СЗ.СЦЕНАРІЇ[назва])
    к = json.loads(B.виклик("запити", json.dumps(dict(вх0, сценарій=сц, випадок=назва), ensure_ascii=False)))["кандидати"]
    кат0 = B.каталог_останнього_пакета(); зі0 = {r["id"]: r for r in кат0}
    г = [(с, r["id"]) for с, рр in к.items() for r in рр if гучна(зі0.get(r["id"]) or {})]   # пари ДО — ті самі для В1
    пари = [(x, y) for с1, x in г for с2, y in г if с1 not in АС.СЛОТИ_АКСЕСУАРІВ and с2 in АС.СЛОТИ_АКСЕСУАРІВ]
    for бік, кат in (("ДО", кат0), ("В1", [в1(r) for r in кат0])):
        зі, rnd = {r["id"]: r for r in кат}, random.Random(7)
        for n in range(10):
            ід = [rnd.choice(к[с])["id"] for с in СЛОТИ if к.get(с) and с not in (("верх", "низ") if n % 2 == 0 else ("сукня",))]
            Л["(а) %s: образів з опорою з 40" % бік] += bool(PL.перевірити_від_моделі(ід, F, кат, T, сценарій=dict(сц), кандидати=к).get("опори"))
        for a, b in пари:
            x, y = зі[a], зі[b]; гр = {"усі", "одне слово"} if x.get("колір_ім") and x.get("колір_ім") == y.get("колір_ім") else {"усі"}
            if not (гучна(x) and гучна(y)): Л["(б) пар випало: вже не гучні за виміром, %s" % бік] += 1; continue   # як `_гучні` у K-ACC-01
            for вар, v in ((бік, КР.поруч_за_тоном(y, x, ДУГА_ВІДЛУННЯ)), (бік + "+В2", КР.поруч_за_тоном(на_колі(y), на_колі(x), 15.0))):
                for g in гр: Л["(б) пар %s, %s: %s" % (g, вар, v)] += 1
for к_, v in sorted(Л.items()): print("  %-50s %5d" % (к_, v))
