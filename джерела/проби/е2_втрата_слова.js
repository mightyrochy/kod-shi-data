function функція(файл, початок, кінець){
  const код = база ? cp.execFileSync('git', ['show', `${база}:джерела/показ/${файл}`], {encoding: 'utf8'})
                   : fs.readFileSync(path.join(джерела, 'показ', файл), 'utf8');
  return код.slice(код.indexOf(початок), код.indexOf(кінець, код.indexOf(початок)));
}
