"""Звірити кожну знахідку блиску й металів з двох знімків: склад, сила, ефективна вага, підлога, блокування."""
import collections, gzip, json, sys


def main():
    """Друк таблиці сирих змін ваги; ефективні зміни, підлога й блокування мусять бути тотожні."""
    def читати(шлях):
        with gzip.open(шлях, 'rt', encoding='utf-8') as ф:
            return json.load(ф)
    до, після = map(читати, sys.argv[1:3])
    assert len(до) == len(після), (len(до), len(після))
    сирі, ефективні, разом = collections.Counter(), collections.Counter(), collections.Counter()
    for д, п in zip(до, після):
        assert д[:6] == п[:6], (д, п)
        разом[д[2], д[5]] += 1
        if д[6] != п[6]:
            сирі[д[2], д[5], д[6], п[6]] += 1
        if д[7:] != п[7:]:
            ефективні[д[2], д[5], tuple(д[7:]), tuple(п[7:])] += 1
    print('знахідок', len(до), '· склад і сила тотожні · сирих змін', sum(сирі.values()),
          '· ефективних змін (вага, підлога, блокує)', sum(ефективні.values()))
    print('за правилом і силою:', sorted(разом.items(), key=str))
    print('| Правило | Сила | ДО | ПІСЛЯ | Кількість |')
    print('|---|---|---|---|---|')
    for (правило, сила, було, стало), кількість in sorted(сирі.items(), key=str):
        print('| %s | %s | %s | %s | %s |' % (правило, сила, було, стало, кількість))
    print('Ефективні зміни:', dict(ефективні))
    sys.exit(1 if ефективні else 0)


if __name__ == '__main__':
    main()
