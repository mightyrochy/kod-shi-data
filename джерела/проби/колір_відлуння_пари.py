# -*- coding: utf-8 -*-
"""КОЛІР-Р2 (рядок 2693): вердикт відлуння на парах ГУЧНИХ речей каталогу руки 1 (C*≥40, `АС._C_речі`, як K-ACC-01)
«одяг (верх, сукня, низ, верхній шар) × аксесуар чи взуття»: ДО — 45° CIELAB (`поруч_за_тоном`), ПІСЛЯ — ±15° кола
художника (`колір_річ.відлуння_тону`). Лічба переходів «так/ні/невідомо» — усі пари, пари одного слова кольору, і
для двох вимірів — смуга Δ на колі (≤15 — один сектор, 15–30 — сусідній, 30–45, >45). Приклади очима: назва, слово
(«~» — колір-вікно слова), hex, Δ CIELAB / Δ коло; межа ±15° (Δ коло 12–18) і сусідні сектори, що були «так».
Запуск із джерела/: python3 проби/колір_відлуння_пари.py"""
import json, sys, random, collections as K; sys.path.insert(0, ".")
import bridge as B, стенд_знімок as СЗ, colorspace as cs, колір_річ as КР, аксесуари_структура as АС, palettes as PS
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
B.виклик("запити", json.dumps(dict(вх, сценарій=СЗ.СЦЕНАРІЇ["офіс·18°C"], випадок="офіс"), ensure_ascii=False))
кат = [r for r in B.каталог_останнього_пакета() if (АС._C_речі(r) or 0) >= 40]
ОД = [r for r in кат if r.get("слот") in ("верх", "сукня", "низ", "верхній_шар")]
АК = [r for r in кат if r.get("слот") in АС.СЛОТИ_АКСЕСУАРІВ or r.get("слот") == "взуття"]
h = lambda r: cs.lch(tuple(r["lab"]))[2]
опис = lambda r: "%s · %s%s %s" % ((r.get("назва") or "")[:34], r.get("колір_ім") or "—", "~" if КР.не_вимір(r) else "", PS._hex(r["lab"]))
Л, П, С = K.Counter(), K.defaultdict(list), K.Counter()
for a in ОД:
    for b in АК:
        до, піс = КР.поруч_за_тоном(a, b, 45.0), КР.відлуння_тону(a, b)
        одне = bool(a.get("колір_ім")) and a.get("колір_ім") == b.get("колір_ім")
        for гр in ("усі",) + (("одне слово",) if одне else ()):
            Л["%-11s %-8s → %-8s" % (гр, до, піс)] += 1
        if одне and до != піс: С["%s %s→%s" % (a["колір_ім"], до, піс)] += 1
        if КР.не_вимір(a) or КР.не_вимір(b): continue
        дц, дк = КР._кут(h(a), h(b)), КР.кут_на_колі(h(a), h(b))
        Л["вимір×вимір Δколо %-6s %s→%s" % ("≤15" if дк <= 15 else "15–30" if дк <= 30 else "30–45" if дк <= 45 else ">45", до, піс)] += 1
        if 12 <= дк <= 18: П["межа ±15° (Δколо 12–18), %s → %s" % (до, піс)].append((дц, дк, a, b))
        elif до != піс: П["змінили вердикт, Δколо %s" % ("15–30" if дк <= 30 else ">30")].append((дц, дк, a, b))
for к_, v in sorted(Л.items()): print("  %-46s %7d" % (к_, v))
print("  пари одного слова, що змінили вердикт, за словом:", ", ".join("%s %d" % кв for кв in С.most_common(8)))
for к_, пп in sorted(П.items()):
    print("\n%s — %d пар; приклади:" % (к_, len(пп)))
    for дц, дк, a, b in random.Random(3).sample(пп, min(6, len(пп))): print("  ΔCIELAB %5.1f · Δколо %5.1f  %s  ×  %s" % (дц, дк, опис(a), опис(b)))
