# -*- coding: utf-8 -*-
"""Рядки 5800, 4623, 5986: пул рук 1–2 на «йозі зранку» (нагода `спорт`, смуга рангу 1–2) — вхід живого запису
пачки 15, сцена 13 (кольори, місце `спорт`, 11:00, +18 °C). Скільки в пулі легінсів, піджаків, пальт, костюмів
і вовни (`вовна_частка` запису каталогу ≥ 30), і на якому рівні рангу нагоди (`композитор_слоти._ранг_нагоди`) стоїть кожна річ.
Контроль — робота й побачення: їхній пул не має рухатись (ранг нагоди там не діє).
Запуск із теки `джерела`: python3 проби/пул_нагода_рух_5800.py"""
import sys, os, json, collections
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge as B, feed as Ф, композитор_слоти as КС
База = dict(json.load(open("стенд_вх.json", encoding="utf-8")), шкіра="#d9b48f", волосся=["#745a3b"], очі="#7a7a4c",
            каталог=Ф.каталог_на_диску("каталог_повний.xml"))
СЦЕНИ = {"йога зранку": (dict(нагода="спорт", місце="спорт", година=11, темп_c=18), tuple(range(1, 9))),
         "робота 09:00": (dict(нагода="робота", місце="офіс", година=9, темп_c=18, дрес_код="business_casual"), (3,)),
         "побачення 19:00": (dict(нагода="побачення", місце="ресторан_районний", дрес_код="smart_casual", година=19, темп_c=18), (3,))}
ГРУПИ = {"легінси": ("легінси",), "піджаки": ("блейзер",), "пальта": ("пальто",), "костюми": ("костюм", "комплект", "костюм_повсякденний")}
for н, (сц, сіди) in СЦЕНИ.items():
    Л, РІВ = collections.Counter(), collections.Counter()
    for сід in сіди:
        r = json.loads(B.виклик("запити", json.dumps(dict(База, сід=сід, сценарій=сц, паспорт=dict(сц), випадок=н), ensure_ascii=False)))
        усі = [x for в in r["кандидати"].values() for x in в]
        Л["речей"] += len(усі)
        for г, тт in ГРУПИ.items():
            Л[г] += sum(1 for x in усі if x.get("тип") in тт)
        вовна = {c.get("id"): c.get("вовна_частка") or 0 for c in B.каталог_останнього_пакета()}
        Л["вовна"] += sum(1 for x in усі if вовна.get(x.get("id"), 0) >= 30)
        if сц["нагода"] == "спорт":
            for с in ("верх", "низ", "верхній_шар", "взуття"):
                РІВ.update("%s %s" % (с, КС._ранг_нагоди(x, (1, 2))) for x in r["кандидати"].get(с) or [])
    print("%s (сідів %d, на сід): %s" % (н, len(сіди), ", ".join("%s %.1f" % (k, v / len(сіди)) for k, v in Л.items())))
    if РІВ:
        print("  рівні рангу нагоди (не перетинає, не покриває): " + ", ".join("%s %.1f" % (k, v / len(сіди)) for k, v in sorted(РІВ.items())))
