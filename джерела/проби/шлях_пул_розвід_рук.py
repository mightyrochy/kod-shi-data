# -*- coding: utf-8 -*-
"""Розбір 3/8: чим руки 1 і 2 РОЗВЕДЕНІ — складом пулу чи лише порядком.

`пакет_моделі.пакет_для_моделі` розводить руку 2 двома ходами: позиційним
(`_розвести` — та сама річ не стоїть на тій самій позиції) і головним
(`різноманітність_пулу.розвести_голови` — перші ГОЛОВА_РУК речей слота руки 1 не
стоять у голові руки 2). Проба показує, що НАБІР id обох ходів не міняє, і поруч —
числа справжнього прогону власника 25.09: скільки речей у пулів рук спільні.
Прогін: python3 проби/шлях_пул_розвід_рук.py
"""
import json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ)
os.chdir(ТУТ)
import різноманітність_пулу as РП
пул = {"верх": [dict(id="р%d" % i) for i in range(8)]}
рука1 = {"верх": [r["id"] for r in пул["верх"]]}
після, n = РП.розвести_голови({с: list(рч) for с, рч in пул.items()}, рука1)
print("ГОЛОВА_РУК = %d (скільки перших речей слота розводиться)" % РП.ГОЛОВА_РУК)
print("рука 1, слот «верх»: %s" % рука1["верх"])
print("рука 2 після розвести_голови: %s" % [r["id"] for r in після["верх"]])
print("посунуто голів: %d | набір id той самий: %s | речей було %d, стало %d"
      % (n, {r["id"] for r in після["верх"]} == set(рука1["верх"]),
         len(пул["верх"]), len(після["верх"])))
print("жодна річ руки 1 з пулу руки 2 не знімається — розведення тільки переставляє")
ФАЙЛ = os.path.join(os.path.dirname(ТУТ), "аудит", "тести", "власник_2026-09-25",
                    "verdykty-0phxvk-2026-09-25-2012.json")
for пр in json.load(open(ФАЙЛ, encoding="utf-8"))["прогони"]:
    сп = пр["спільне"]
    if not сп.get("пул_спільних"):
        continue
    різн = ((сп.get("етапи") or {}).get("прогін") or {}).get("різноманітність") or {}
    print("прогін розклад %s (%s): пул %s, речей у пулі %s, СПІЛЬНИХ у рук 1 і 2 — %s"
          % (сп.get("розклад"), сп.get("дата"), сп.get("пул"),
             ((сп.get("етапи") or {}).get("прогін") or {}).get("пул_речей"), сп["пул_спільних"]))
    for рука, звіт in sorted(різн.items()):
        print("   рука %s: голів руки 1 розведено %s, бажання %s"
              % (рука, звіт.get("голів_руки_1_розведено", 0), звіт.get("бажання")))
