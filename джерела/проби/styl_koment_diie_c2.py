# -*- coding: utf-8 -*-
"""С-2 · КОМЕНТАР ДО ОБРАЗУ ДІЄ: «взуття не моє, хочу без каблука» → наступний збір.

Доти внутрішня мова коментаря (`КОМЕНТАР_ВЕРДИКТУ`) їхала лише в журнал. Проба міряє
той самий прогін двічі — без коментаря й після нього (`мовний_шар.паспорт_з_коментаря`):
позначена річ у пулі рук 1–2 та взуття з ОГОЛОШЕНИМ каблуком у пулі руки 1.
Запуск: cd джерела && python3 проби/styl_koment_diie_c2.py [файл каталогу]"""
import collections, json, os, sys
Д = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, Д); os.chdir(Д)
import bridge as B, feed as Ф, мовний_шар as МШ, міст_пакет as МП, pipeline as PL
КАТ = sys.argv[1] if len(sys.argv) > 1 else ("каталог_повний.xml" if os.path.exists("каталог_повний.xml") else "каталог_brief.xml")
СЦ = dict(нагода="робота", місце="офіс_корпоративний", дрес_код="business_casual")
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), каталог=Ф.каталог_на_диску(КАТ),
          варіантів=1, сценарій=dict(СЦ, година=11, темп_c=18),
          паспорт=dict(СЦ, перекладено_шаром=True))
пул = lambda r, сл: [x["id"] for x in ((r.get("кандидати") or {}).get(сл) or [])]
донор = lambda r, сл: [x["id"] for x in ((r.get("кандидати_донора") or {}).get(сл) or [])]
без = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
каблуки = lambda: {r.get("id") for r in (МП._КЕШ_ПАКЕТА.get(МП._ОСТАННІЙ_ПАКЕТ[-1]) or {}).get("_каталог") or []
                   if r.get("слот") == "взуття" and r.get("каблук_є") is True}
каблук_до = каблуки() & set(пул(без, "взуття"))
ціль = next((x for x in пул(без, "взуття") if x in донор(без, "взуття")), пул(без, "взуття")[0])
# внутрішня мова коментаря — те, що віддає перекладач картки (кодами, без її слів)
дія = json.loads(МШ.мова({"коментар_з": {"about_items": [{"id": ціль, "opinion": "dislike"}],
                                         "vetoes": [{"feature": "heels"}],
                                         "wants": [{"item_type": "sneakers"}]},
                          "паспорт": вх["паспорт"]}))
після = json.loads(B.виклик("запити", json.dumps(
    dict(вх, паспорт=дія["паспорт"], не_ця=дія["не_ця"]), ensure_ascii=False)))
каблук_після = каблуки() & set(пул(після, "взуття"))
лічба = lambda r: ((r.get("відсічено") or {}).get("лічба") or {})
print("ФАКТ · %s · коментар долив: межі %s · бажання %s"
      % (КАТ, json.dumps(дія["додано"]["вето"], ensure_ascii=False), дія["додано"]["бажання"]))
print("ФАКТ · позначена річ «%s» у пулі: рука 1 %s → %s · рука 2 %s → %s"
      % (ціль, ціль in пул(без, "взуття"), ціль in пул(після, "взуття"),
         ціль in донор(без, "взуття"), ціль in донор(після, "взуття")))
print("ФАКТ · взуття з оголошеним каблуком у пулі руки 1: %d → %d (усього взуття %d → %d)"
      % (len(каблук_до), len(каблук_після), len(пул(без, "взуття")), len(пул(після, "взуття"))))
print("ФАКТ · відсічення «%s»: %d → %d · лічба після: %s"
      % (PL.ПРИЧИНА_НЕ_ЦЯ, лічба(без).get(PL.ПРИЧИНА_НЕ_ЦЯ, 0), лічба(після).get(PL.ПРИЧИНА_НЕ_ЦЯ, 0),
         json.dumps(лічба(після), ensure_ascii=False)))
