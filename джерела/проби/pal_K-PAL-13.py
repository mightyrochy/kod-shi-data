# -*- coding: utf-8 -*-
"""K-PAL-13 (сивина) — «без сліду» розібрано: гілка жива, входу на стенді нема.

Аудит (ЗВЕДЕННЯ K-PAL-13): «є в коді, на живому шляху не виконується». Причина —
ВХІД, не логіка: прийом умикається лише на ахроматичному волоссі
(`palettes.прийоми`: `волосся_ахроматичне`), а стендова жінка має волосся
#f1dbaa — C*26.9 при порозі `colorspace.ACHROMATIC_C`. Доти мовчання правила без
входу було невідрізненне від «пройдено».
ПІСЛЯ — дві речі: (1) `суд_образу.ЧЕКЛІСТ_ПАЛІТРИ` пункт P5 стоїть у стані «без
входу», і це видно у `вердикт.образи[].чекліст.палітра`; (2) на волоссі, яке
температури не несе, правило судить: очі лишаються єдиним акцентом від рис, і
образ без їхньої сім'ї біля обличчя дає знахідку.
Запуск із теки `джерела`: `python3 проби/pal_K-PAL-13.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import palettes as PAL, personal_palette as PP, colorspace as cs, суд_образу as СО
import bridge as B, json

# 1. ВХІД: та сама людина з сивим волоссям і без нього — через ті самі `входи_палітри`
for hex_волосся, мітка in (("#f1dbaa", "стендове волосся"), ("#b9b9b9", "сиве волосся")):
    вх = json.load(open(pathlib.Path(__file__).resolve().parent.parent / "стенд_вх.json", encoding="utf-8"))
    вх["волосся"] = [hex_волосся]
    F = B._features(вх)[0]          # `_features` віддає кортеж; риси — перший елемент
    вхп = СО.входи_палітри(F, "uncontrolled")
    П = PAL.палітра_практична(F, source="uncontrolled")
    акт = {x["прийом"] for x in П["прийоми"] if x["активний"]}
    C = (PP._дані(F).get("волосся") or {}).get("C")
    print("%-18s C* волосся %.1f (поріг ахромату %.1f) · вхід «ахроматичне волосся»: %s · прийом «сивина» активний: %s"
          % (мітка, C or 0.0, cs.ACHROMATIC_C, вхп.get("сивина"), "сивина" in акт))

# 2. ЧЕКЛІСТ: пункт P5 на стендовій жінці мусить стояти «без входу», а не «пройдено»
вх, r, кат, спец = ПВ.стенд(гілка=0)
ід = [x["id"] for x in [ПВ.взяти(r, кат, с, lambda *a: True) for с in ("верх", "низ", "взуття", "сумка")] if x]
зн, вм = ПВ.знахідки(вх, ід)
чк = ((вм.get("вердикт") or {}).get("образи") or [{}])[0].get("чекліст") or {}
пал = чк.get("палітра") or {}
print("ФАКТ · чекліст палітри у вердикті: провалів %d, пройдено %s, без входу %s"
      % (len(пал.get("провал") or []), пал.get("пройдено"), пал.get("без_входу")))
print("       K-PAL-13 у знахідках: %s" % ПВ.рядок(зн, "K-PAL-13"))
assert пал, "третій чекліст не доїхав до вердикту"
assert (пал.get("без_входу") or 0) >= 1, "жодного «без входу» — вимкнене вдає пройдене"
