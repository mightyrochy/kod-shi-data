"""Звірити знахідки `верхнє_довжина` двох знімків (каталог чи гейти): склад і заяви; таблиці змін сили й ваги."""
import collections, gzip, json, sys


def main():
    """Склад, суть, речі й заяви тотожні; друк змін сили, сирої й ефективної ваги за правилом."""
    до, після = (json.load(gzip.open(ш, 'rt', encoding='utf-8')) for ш in sys.argv[1:3])
    до, після = (д['записи'] if isinstance(д, dict) else д for д in (до, після))   # знімок гейтів — dict
    assert len(до) == len(після), (len(до), len(після))
    сирі, ефективні = collections.Counter(), collections.Counter()
    for д, п in zip(до, після):
        assert д[:5] == п[:5] and д[8] == п[8], (д, п)
        сила = д[5] if д[5] == п[5] else '%s → %s' % (д[5], п[5])
        if д[6] != п[6] or д[5] != п[5]:
            сирі[д[2], сила, д[6], п[6]] += 1
        if д[7] != п[7]:
            ефективні[д[2], сила, д[7], п[7]] += 1
    print('знахідок', len(до), '— склад, суть, речі й заяви тотожні; сила змінилась у',
          sum(1 for д, п in zip(до, після) if д[5] != п[5]), '; сирих змін', sum(сирі.values()),
          'ефективних', sum(ефективні.values()))
    for назва, т in (('сирі', сирі), ('ефективні', ефективні)):
        print('\n%s: | правило | сила | ДО | ПІСЛЯ | кількість |' % назва)
        for (пр, с, було, стало), к in sorted(т.items(), key=str):
            print('| %s | %s | %s | %s | %s |' % (пр, с, було, стало, к))


if __name__ == '__main__':
    main()
