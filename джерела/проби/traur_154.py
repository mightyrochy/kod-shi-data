    великі = [ТР.траурний_регістр_речі(КАТ[i])["стан"] for i in ід if КАТ[i]["слот"] in ТР.ВЕЛИКІ_ПОВЕРХНІ_ТРАУРУ]
    гейти = sum(1 for о in вм["образи"] if any(з.get("правило") == "K-OCC-01" and з.get("регістр") == "гейт" for з in о.get("знахідки") or []))
    return [великі.count(с) for с in ("так", "здебільшого", "ні")], [ТР.святкова_оздоба(КАТ[i]) for i in ід if ТР.святкова_оздоба(КАТ[i])], гейти, len(вм["образи"])
