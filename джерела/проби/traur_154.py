def прогін(пасп, траур):
    пасп = dict(пасп, рух="стояти", намір="conventional", бажання=[], вето=В0, темп_c=12, опади="ні", невідомо=[], питання_людині=[])
    вх = dict(json.load(open("стенд_вх.json")), сід=3, сценарій=dict({k: пасп[k] for k in ("нагода", "місце", "година", "темп_c")}, **({"траур": траур} if траур else {})))
    вх["паспорт"] = json.loads(B.виклик("паспорт", json.dumps(dict(json_моделі=json.dumps(пасп), сценарій=вх["сценарій"]))))["паспорт"]
    B.виклик("палітри", json.dumps(вх)); пул = json.loads(json.loads(B.виклик("запити", json.dumps(вх)))["руки"]["1"])["пул"]
    в = lambda с, i: пул[с][i % len(пул[с])]["н"] if пул.get(с) else None
    тр = [с for с in ТРЕТІ if пул.get(с)]
    образи = [dict(ід="о%d" % i, підпис="проба", полюс="вільний", речі=[x for x in ([в("сукня", i)] if (пул.get("сукня") and i % 2) else [в("верх", i), в("низ", i)])
              + [в("взуття", i), в("сумка", i), в(тр[i % len(тр)], i) if тр else None] if x]) for i in range(1, 11)]
    вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=json.dumps(dict(версія="1", образи=образи))))))
