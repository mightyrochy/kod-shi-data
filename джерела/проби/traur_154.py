        ТР.траурне_відсічення = справжнє if мітка == "ПІСЛЯ" else (lambda r, тр: None); МП._КЕШ_ПАКЕТА.clear()
        (так, здеб, ні), оздоби, гейти, n = прогін(пасп, траур)
