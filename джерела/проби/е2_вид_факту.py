"""Е2-межі п.3 (рішення менеджера 31.10): вид години й нагоди в картці за її словами — цифрами, словами, порою."""
import contextlib, io, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
with contextlib.redirect_stdout(io.StringIO()):
    import мовний_шар as М

СЦЕНИ = [  # її слова, hour моделі
    ("Весілля подруги о 19", {"quote": "о 19", "value": 19, "named": "clock_time"}),
    ("Весілля подруги, початок 19:30", {"quote": "19:30", "value": 19, "named": "clock_time"}),
    ("Весілля подруги о сьомій вечора", {"quote": "о сьомій вечора", "value": 19, "named": "clock_time"}),
    ("Весілля подруги в суботу ввечері", {"quote": "в суботу ввечері", "value": 19, "named": "clock_time"}),
    ("Весілля подруги в суботу ввечері", {"quote": "в суботу ввечері", "value": 19}),
]
її_без_цифр = 0
for слова, година in СЦЕНИ:
    відповідь = {"update": {"occasion": {"quote": "Весілля подруги", "value": "wedding_guest"}, "hour": година},
                 "text": "Записала.", "invite": ""}
    прийнято = М.прийняти_розмову(json.dumps(відповідь, ensure_ascii=False))
    with contextlib.redirect_stdout(io.StringIO()):
        п = М.паспорт_з_шару(прийнято.get("внутрішня") or {}, {}, слова_ходу=[слова])["паспорт"]
    к = п.get("картка_запиту", {})
    г, н, пора = к.get("година", {}), к.get("нагода", {}), к.get("пора", {})
    її_без_цифр += int(г.get("джерело") == "her" and not any(ч.isdigit() for ч in г.get("уривок", "")))
    print("%-36s година=%s/%s «%s» · пора=%s/%s · нагода=%s/%s «%s»" % (
        слова, г.get("значення"), г.get("джерело"), г.get("уривок", ""), пора.get("значення"), пора.get("джерело"),
        н.get("значення"), н.get("джерело"), н.get("уривок", "")))
print("її годин без цифр в уривку:", її_без_цифр)
