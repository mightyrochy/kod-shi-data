"""Рядок 201 (питання власника 24.09.2026: «чи можна по вердикту робити висновки?»). Знахідка суду адресує річ
ід-ом («ж-08152@miraton.ua») і номером пулу («#11·19»); у звіті поруч з ід стояли лише назва, слот, ціна й урл —
без КОЛЬОРУ, КРАМНИЦІ й АДРЕСИ ФОТО, тобто K-CLR-* читати було нічим, а подивитись на річ — ніде. Проба рахує на
шести сценах стенда, скільки полів `міст_опис.показ` дає на річ ДО і ПІСЛЯ. Запуск із теки `джерела`:
`python3 проби/довідник_речей_201.py`."""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import стенд_знімок as СЗ, міст_опис as МО, bridge as B   # шлях показу, не копія його логіки
ДО = ("назва", "слот", "ціна", "урл", "фото")             # що звіт мав про річ до правки
ДОДАНО = ("колір", "крамниця", "категорія")               # що додано в `показ` рядком 201
СЛОТИ = ("сукня", "верх", "низ", "верхній_шар", "взуття", "сумка", "прикраси", "пояс", "шарф")
КАТ = "каталог_повний.xml" if os.path.exists("каталог_повний.xml") else "каталог_brief.xml"

def образ_сцени(сцен):
    """Картки речей сцени — тим самим `міст_опис.показ`, яким їх бачить показ і звіт."""
    вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["сценарій"] = сцен
    к = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False))).get("кандидати") or {}
    ід = [к[с][0]["id"] for с in СЛОТИ if к.get(с) and к[с][0].get("id")]
    return json.loads(МО.показ(dict(каталог=КАТ, речі=ід))) if ід else []

def є(р, к): return р.get(к) not in (None, "", [], {})

print("сцена                     речей  ДО полів/річ  ПІСЛЯ  з кольором  з крамницею  з фото"); разом = [0, 0, 0, 0]
for назва, сцен in list(СЗ.СЦЕНАРІЇ.items())[:6]:
    речі = образ_сцени(сцен)
    до = sum(len([к for к in ДО if є(р, к)]) for р in речі)
    після = до + sum(len([к for к in ДОДАНО if є(р, к)]) for р in речі)
    кольором = len([р for р in речі if є(р, "колір")])
    крамницею = len([р for р in речі if є(р, "крамниця")])
    фото = len([р for р in речі if є(р, "фото")])
    разом = [разом[0] + len(речі), разом[1] + до, разом[2] + після, разом[3] + кольором]
    print("%-24s %6d %13.1f %6.1f %11d %12d %7d" % (назва[:24], len(речі),
          до / max(1, len(речі)), після / max(1, len(речі)), кольором, крамницею, фото))
    assert після >= до, "полів на річ не може поменшати"
print("РАЗОМ речей %d · полів про річ у звіті: ДО %d · ПІСЛЯ %d (+%d %%) · з названим кольором %d"
      % (разом[0], разом[1], разом[2], round((разом[2] - разом[1]) * 100 / max(1, разом[1])), разом[3]))
print("Ті самі поля стоять у файлі вердиктів поруч з ід — `етапи.довідник_речей` і `речі_образу`.")
assert разом[3] > 0 and разом[2] > разом[1]
print("довідник_речей_201: зелено")
