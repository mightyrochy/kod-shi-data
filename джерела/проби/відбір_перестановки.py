"""Міряє 30 перестановок речей каталогу й узгодження цілі повноти з ремонтом."""
import json, pathlib, random, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import feed, семплер as С, повнота_образу as П, порядок_запиту as З


def головна():
    """Друкує розбіжності на тому самому вході за незмінного сіда."""
    каталог = pathlib.Path(__file__).resolve().parents[1] / 'каталог_brief.xml'
    речі = feed.база_прогону(str(каталог), ліміт_фото=0)['каталог']
    слот = next(с for с in sorted({р.get('слот') for р in речі if р.get('слот')})
                if sum(р.get('слот') == с for р in речі) >= 20)
    пул = [р for р in речі if р.get('слот') == слот]
    виходи, дріт, ремонти = [], [], []
    for н in range(30):
        вхід = list(пул); random.Random(н).shuffle(вхід)
        виходи.append([р['id'] for р in С.вибрати_зі_слота(вхід, 7, 4242)])
        дріт.append([р['id'] for р in З.перемішати(вхід, 0)])
        образи = [dict(ід='о1', речі=['а', 'б'], структура=dict(ок=False,
                    блокери=[dict(код='слот_двічі'), dict(код='слот_двічі')])),
                  dict(ід='о2', речі=['а', 'б', 'в'], структура=dict(ок=False,
                    блокери=[dict(код='слот_двічі')]))]
        random.Random(н).shuffle(образи)
        кандидати = {'верх': [dict(id=і, слот='верх') for і in 'абв']}
        вердикт = dict(образи=образи)
        ціль = П.повнота_набору(вердикт, кандидати=кандидати)['образ']
        ремонт = П.вердикт_повноти(вердикт)
        ремонти.append(ремонт['образи'][0]['ід'] != ціль)
    факти = dict(каталог=каталог.name, слот=слот, речей=len(пул), перестановок=30,
                 семплер=sum(в != виходи[0] for в in виходи),
                 дріт_без_сіда=sum(в != дріт[0] for в in дріт), чужий_ремонт=sum(ремонти))
    print(json.dumps(факти, ensure_ascii=False))
    return int(any(факти[к] for к in ('семплер', 'дріт_без_сіда', 'чужий_ремонт')))


if __name__ == '__main__':
    sys.exit(головна())
