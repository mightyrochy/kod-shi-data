"""Проба (рядок 2624): «надворі мороз» без градусів — ті самі знахідки погоди, що й з −8 °C у паспорті (як на
e79ad9f4, до #627). Пул (`запити`, каталог_повний) і `від_моделі` над образом футболка + низ + взуття + сумка + перша
нетепла верхня річ пулу, для двох паспортів: `темп_c: −8` (форма e79ad9f4) і `погода_відчуття: frost` (форма після
#627; поле форми — типові 18 °C). Друкує число правил, пальта пулу, `day` для моделей і знахідки K-WEA / K-OUT;
рядок 2844 — значення заяви `weather_needs_outerwear` на рядку картки образу без верхнього шару. Моделі не кличе. Запуск: cd джерела && python3 проби/мороз_відчуття_2624.py"""
import json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed as Ф, bridge as B, міст_пакет as МП, верхнє_погода as ВП, сценарій as СЦ, суд_погода as СП  # noqa: E401
база_вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), гілка=0,
              каталог=Ф.каталог_на_диску("каталог_повний.xml"))
мітка = lambda r: (ВП.ТЕПЛОВІ_ФУНКЦІЇ.get(r.get("тип_верхнього") or r.get("тип")) or ("?",))[0]
ПАСПОРТИ = {"темп_c −8 (e79ad9f4)": {"темп_c": -8}, "погода_відчуття frost": {"погода_відчуття": "frost"}}
for назва, пп in ПАСПОРТИ.items():
    п = dict({"джерело": "модель", "нагода": "робота", "місце": "офіс", "година": 9, "перекладено_шаром": True}, **пп)
    вх = dict(база_вх, сценарій=dict(база_вх["сценарій"], темп_c=18, типові_поля=["темп_c"]), паспорт=п,
              випадок="робочий день, офіс, 09:00")
    сцен = СЦ.з_показу(вх["сценарій"], п)[0]
    МП._КЕШ_ПАКЕТА.clear()
    B.виклик("запити", json.dumps(вх, ensure_ascii=False))
    кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
    канд = [p for p in МП._КЕШ_ПАКЕТА.values() if p.get("кандидати")][0]["кандидати"]
    вш = [кат.get(r["id"], r) for r in канд.get("верхній_шар") or []]
    print("%s: число правил %s · пальтова смуга %s · day=%s" % (назва, сцен.get("темп_c"),
          СП.пальтова_смуга(сцен.get("темп_c")), json.dumps(СЦ.день_кодами(сцен), ensure_ascii=False)))
    print("   пул: верхніх %d · справжніх пальт %d" % (len(вш), len(СП.пальта_пулу(канд))))
    нетепла = next(r for r in вш if мітка(r) in ("частково", "майже ні", "ні"))
    ід = [next(c["id"] for c in кат.values() if c.get("слот") == с and (с != "верх" or c.get("тип") == "футболка"))
          for с in ("верх", "низ", "взуття", "сумка")] + [нетепла["id"]]
    о = ((json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False))).get("вердикт") or {})
         .get("образи") or [{}])[0]
    зн = sorted("%s %s/%s" % (z.get("правило"), z.get("сила"), z.get("регістр")) for z in о.get("знахідки") or []
                if str(z.get("правило", "")).startswith(("K-WEA", "K-OUT")))
    print("   образ з «%s»: %s" % (нетепла["назва"][:30], "; ".join(зн) or "знахідок погоди нема"))
    р = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід[:4]), ensure_ascii=False)))
    з = [x.get("values") for x in ((р.get("повнота") or {}).get("рядок") or {}).get("statements") or []
         if x.get("code") == "weather_needs_outerwear"]
    print("   образ без верхнього шару: рядок картки weather_needs_outerwear %s" % json.dumps(з, ensure_ascii=False))
