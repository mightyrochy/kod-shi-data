"""КОЛО-РОЛІ (рядок 4780/4781, кеш очей): `_ключ_запиту` несе поля запису очей, не лише їх наявність. Два запити з
однаковими межами й різними очима (червоні/зелені) → різні ключі й різні частки вікна слова-кольору «зелений».
Запуск із джерела/: python3 проби/коло_ролі_кеш_очей.py"""
import sys; sys.path.insert(0, ".")
import colorspace as cs, palettes as ПЛ, фід_добір as Ф
def q(hex_):
    L, C, h = cs.lch(cs.hx(hex_)); д = ПЛ.дуга_очей(h)
    return dict(L_min=0.0, L_max=100.0, C_min=0.0, C_max=1000.0, h_from=д[0], h_to=д[1],
                очі_запис=ПЛ.колір_очей(dict(L=L, C=C, h=h)))
а, б = q("#a83232"), q("#3a8f4a")
вікно = (30.0, 70.0, 20.0, 60.0, (100.0, 160.0))   # L, C, дуга тону — зелене слово
print("ключі різні:", Ф._ключ_запиту(а) != Ф._ключ_запиту(б))
print("частки червоні/зелені: %s / %s" % (Ф.частка_вікна(вікно, а), Ф.частка_вікна(вікно, б)))
