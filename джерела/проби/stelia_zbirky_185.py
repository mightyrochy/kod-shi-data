# -*- coding: utf-8 -*-
"""Рядок 185: стеля збірки показу — в БАЙТАХ, і чистка показу нічого не міняє.

Друкує факт: скільки байтів знімає `_чистка_показу`, скільки коментарів JS вона
прибрала і чи лишились рядки-літерали символ у символ. Плюс різниця «символи
проти байтів», через яку гейт міряв не той продукт, що їде на Pages.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import build_артефакт as B

Б = lambda т: len(т.encode("utf-8"))
сирий = open(os.path.join(os.path.dirname(B.__file__), "показ.html"), encoding="utf-8").read()
чистий = B._чистка_показу(сирий)

js = lambda т: "\n".join(м.group(1) for м in __import__("re").finditer(
    r"<script>(.*?)</script>", т, __import__("re").S))
к0, л0 = B._спани_js(js(сирий))
к1, л1 = B._спани_js(js(чистий))
тексти0 = [js(сирий)[а:б] for а, б in л0]
тексти1 = [js(чистий)[а:б] for а, б in л1]

print("показ.html: %d → %d байт (знято %d)" % (Б(сирий), Б(чистий), Б(сирий) - Б(чистий)))
print("коментарів JS: %d → %d" % (len(к0), len(к1)))
print("рядків-літералів JS: %d → %d, символ у символ: %s"
      % (len(тексти0), len(тексти1), тексти0 == тексти1))
print("стеля показу: %d байт (СТЕЛЯ_ПОКАЗУ), артефакта: %d байт"
      % (B.СТЕЛЯ_ПОКАЗУ, B.СТЕЛЯ_АРТЕФАКТА))
print("символи проти байтів на цьому ж файлі: %d символів, %d байт — різниця %d (%.1f %%)"
      % (len(сирий), Б(сирий), Б(сирий) - len(сирий),
         100.0 * (Б(сирий) - len(сирий)) / len(сирий)))

збірка = os.path.join(os.path.dirname(os.path.dirname(B.__file__)), "index.html")
if os.path.exists(збірка):
    р = os.path.getsize(збірка)
    print("index.html у дереві: %d байт, запас до стелі %d (%.1f %%)"
          % (р, B.СТЕЛЯ_ПОКАЗУ - р, 100.0 * (B.СТЕЛЯ_ПОКАЗУ - р) / B.СТЕЛЯ_ПОКАЗУ))
assert к1 == [] and тексти0 == тексти1, "чистка зачепила код, а не коментарі"
