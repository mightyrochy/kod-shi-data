# -*- coding: utf-8 -*-
"""Усі сім смуг проходять від паспорта до добору, суду й дроту без градусів."""
import os, sys, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import сценарій as С
import паспорт_нагоди as П
import суд_погода as W
import пакет_моделі as М
import оцінка_образу as О
import verify as V
import outfit as F
import profile as ПР

if __name__ == '__main__':
    assert ПР.ПОГОДА_КОНТРАКТ['смуга_погоди']['значення'] == list(С.СМУГИ_ПОГОДИ)
    р = dict(id='сандалі', слот='взуття', тип='сандалі', назва='Сандалі', підошва='гладка')
    for код in С.СМУГИ_ПОГОДИ:
        сц, чужі = П.з_показу({}, {'смуга_погоди': код})
        assert not чужі and сц['смуга_погоди'] == код
        assert W.смуга_ніг(код) and F.ТЕМП_МАПА[код]
        зн = W.сезон_і_погода([р], сц['смуга_погоди'], 'сніг')
        assert not any('темп_c' in str(з) for з in зн)
        assert not any('смуга_погоди' in (з.get('немає_входу') or []) for з in зн)
        W.погода([], смуга_погоди=код, речі=[р], стан="надворі")
        М.жорстке_відсічення(р, смуга_погоди=код)
        тканина = V.сезон_тканини_зі_слова('Штани з льону')['смуга']
        assert V.поза_смугою_тканини(тканина, код) is not None
        assert О.сценарій_оцінки({}, {'weather_band': код})[0]['смуга_погоди'] == код
        assert О.сценарій_оцінки({}, паспорт={'смуга_погоди': код})[0]['смуга_погоди'] == код
        assert С.день_кодами(сц)['weather_band'] == код
        assert W.погода_значеннями(код)['weather_band'] == код
    assert W.сезон_і_погода([р], 'frost', 'сніг') != W.сезон_і_погода([р], 'hot', 'ні')
    assert С.сіль_на_дорозі(None, 'frost', 'сніг')[0]
    assert not С.сіль_на_дорозі(None, 'cold', 'сніг')[0]
    assert W.відстань_смуг(W.смуга_типу('сандалі'), 'frost') > 1
    assert not W.пальтова_смуга(None) and W.пальтова_смуга('cold')
    assert W.смуга_ніг('invented') is None and С.канон_опади('так', 'frost') is None
    print('читачі смуги: 7/7; суд, пул, тканини, оцінка, сіль, повнота й дріт — пройдено')
