"""Ділянка 8: «Я ЗАРАЗ НЕ БАЧУ: ТИ НЕ ДОДАЛА ФОТО» — а фото є. Міряє, скільки зображень справді
їде в модель на першому й на другому ході однієї розмови, і що саме бачить помічниця, яка це
речення пише. Друкує відбір `новіФотоРечейП`, підпис фото в тексті репліки й шлях виклику.
Запуск із `джерела`: python3 проби/шлях_оцінка_фото_хід2.py"""
import sys, re; sys.path.insert(0, '.')
T = open('показ.html', encoding='utf-8').read()
ряд = lambda взір: T[:re.search(взір, T).start()].count('\n') + 1
відбір = re.search(r'function новіФотоРечейП\(\)\{(.*?)\n\}', T, re.S).group(1)
print('відбір фото у виклик (показ.html:%d):' % ряд(r'function новіФотоРечейП'))
for р in [x.strip() for x in відбір.strip().split('\n')]:
    print('   ' + р)
print('→ фото, річ якого вже названа в паспорті, у «відомі» — і в модель БІЛЬШЕ НЕ ЇДЕ')
print('блоки зображень чіпляються лише коли список непорожній (показ.html:%d): %s'
      % (ряд(r'const модельЗФото'), re.search(r'const модельЗФото = .*', T).group(0).strip()))
print('у тексті репліки лишається лише підпис (показ.html:%d): %s'
      % (ряд(r"return '\[фото ' \+ фото"), re.search(r"return '\[фото ' \+ фото.*", T).group(0).strip()))
# ті самі три рядки, переписані на Python: вхід — стрічка репліки й паспорт ходу
нові = lambda репліки, паспорт: [ф for р in репліки if р['хто'] == 'людина' for ф in р.get('фото', [])
                                 if ф.get('дані') and ф['ід'] not in
                                 {р2['фото'] for р2 in паспорт.get('речі_з_фото', []) if р2.get('назва')}]
ФОТО = [dict(ід='ф1', дані='…'), dict(ід='ф2', дані='…')]
РЕПЛ = [dict(хто='людина', текст='Мене цікавить чи поєднуються ці кольори…', фото=ФОТО)]
ПАСП2 = dict(речі_з_фото=[dict(фото='ф1', назва='жакет приталений'), dict(фото='ф1', назва='сорочка'),
                          dict(фото='ф1', назва='міні'), dict(фото='ф1', назва='клатч'),
                          dict(фото='ф2', назва='ботильйони')])
for підпис, пасп, репл in (('хід 1: фото щойно надіслано, паспорт порожній', {}, РЕПЛ),
                           ('хід 2: та сама розмова, речі вже названі', ПАСП2,
                            РЕПЛ + [dict(хто='ші', текст='…'), dict(хто='людина', текст='Мене цікавить просто наскільки…')])):
    print('%-50s → зображень у виклик 0: %d' % (підпис, len(нові(репл, пасп))))
пом = T[re.search(r'async function помічникП', T).start():][:760]
print('а ЇЇ ПИТАННЯ пише помічниця (показ.html:%d) одним текстовим викликом: %s'
      % (ряд(r'async function помічникП'), re.search(r'return String\(await модельП\(.*', пом).group(0).strip()))
print('→ `модельП(промпт)` — БЕЗ другого аргументу, тобто без жодного зображення НА ОБОХ ходах:')
print('  помічниця не бачить фото ніколи, і «не додала фото» — правда про її власний вхід,')
print('  а не про повідомлення жінки; промпт велить їй казати саме це (`Не вигадуй: чого нема…`)')
