import glob, json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import мовний_шар as М

print("сталі, симв.: ВИХОДУ %d · з ПРАВИЛО_РЕЧЕЙ %d · РЕПЛІКИ %d · ПОВІДОМЛЕНЬ %d" % (
    len(М.ПРОМПТ_ВИХОДУ), len(М.ПРОМПТ_ВИХОДУ) + len(М.ПРАВИЛО_РЕЧЕЙ), len(М.ПРОМПТ_РЕПЛІКИ), len(М.ПРОМПТ_ПОВІДОМЛЕНЬ)))
print("«ніколи «ви»» у ВИХОДУ/РЕПЛІКИ/ПОВІДОМЛЕНЬ:", [т.count("ніколи «ви»") for т in
      (М.ПРОМПТ_ВИХОДУ, М.ПРОМПТ_РЕПЛІКИ, М.ПРОМПТ_ПОВІДОМЛЕНЬ)], "· «Про жінку» абзаців:", М.ПРОМПТ_ВИХОДУ.count("Про жінку"))
print("pumps у ВИХОДУ/ПРАВИЛО_РЕЧЕЙ/МОВА_ДЛЯ_НЕЇ:", [т.count("pumps") for т in (М.ПРОМПТ_ВИХОДУ, М.ПРАВИЛО_РЕЧЕЙ, М.МОВА_ДЛЯ_НЕЇ)],
      "· boots у ВИХОДУ:", re.findall(r"(?<!ankle )boots — [^,;]+", М.ПРОМПТ_ВИХОДУ))
р = [dict(н=1, ключ="а", текст="Silk slip dress")]
