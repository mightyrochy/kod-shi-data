"""Звірити кожну знахідку силуету образу й регістру уваги з двох знімків; таблиця змін ваги."""
import collections, gzip, json, sys

# Літерали без джерела K-SIL-10 (`суд_силует.карта_спідниць`): міді — вага категорії hint (округлення до щабля),
# максі — сила щаблем нижче, soft (рішення менеджера 15571; паспорт кореня).
ДОЗВОЛЕНІ = {('K-SIL-10', 'hint', 0.2, 0.25)}
СИЛА = {('K-SIL-10', 'default', 'soft')}


def та_сама(д, п):
    """Та сама знахідка: склад однаковий, сила — та сама чи названа в `СИЛА`."""
    return д[:5] == п[:5] and (д[5] == п[5] or (д[2], д[5], п[5]) in СИЛА)


def main():
    """Склад, сила й підлога тотожні; ефективна вага змінюється лише на названих літералах."""
    читати = lambda ш: json.load(gzip.open(ш, 'rt', encoding='utf-8'))
    до, після = map(читати, sys.argv[1:3])
    assert len(до) == len(після), (len(до), len(після))
    сирі, еф, сила = collections.Counter(), collections.Counter(), collections.Counter()
    for д, п in zip(до, після):
        assert та_сама(д, п) and д[8] == п[8], (д, п)
        if д[5] != п[5]:
            сила[д[2], д[5], п[5], д[7], п[7]] += 1
        if д[6] != п[6]:
            сирі[д[2], д[5], д[6], п[6]] += 1
        if д[7] != п[7]:
            еф[д[2], д[5], д[7], п[7]] += 1
    print('знахідок', len(до), '; склад і підлога тотожні; сирих змін', sum(сирі.values()),
          '; після стелі', sum(еф.values()), '; сили (правило, ДО, ПІСЛЯ, вага ДО, ПІСЛЯ):', dict(сила))
    print('| Правило | Сила | ДО | ПІСЛЯ | Кількість | Ефективна | Чому |')
    print('|---|---|---|---|---|---|---|')
    for к, n in sorted(сирі.items(), key=str):
        print('| %s | %s | %s | %s | %d | %s | %s |' % (*к, n, 'змінилась' if к in еф else 'та сама',
              'літерал без джерела → вага категорії' if к in ДОЗВОЛЕНІ else
              'літерал без джерела → сила щаблем нижче (15571)' if (к[0], к[1], 'soft') in СИЛА else
              'стеля категорії в конструкторі'))
    assert set(еф) <= ДОЗВОЛЕНІ, dict(еф)


if __name__ == '__main__':
    main()
