"""ФОКУС-3 (рядок 1520, огляд #616): зони мети «приховати» в паспорті між ходами розмови — шов
`мовний_шар.паспорт_з_шару` → `паспорт_нагоди.паспорт_з_json`. Зона живе лише з метою, яку уточнює:
мета, названа ходом без зон, скидає давні; хід без мети їх лишає; мета без цитати не береться.
Запуск із джерела/: python3 проби/фокус3_зони_ходи.py"""
import sys; sys.path.insert(0, "."); import мовний_шар as М
def хід(в, досі, слова):
    return М.паспорт_з_шару(в, {}, паспорт_досі=досі, слова_ходу=слова)["паспорт"]
ходи = [("сховати живіт", dict(goal="conceal", goal_zones=["belly"])), ("на роботу", dict(occasion="work")),
        ("хочу, щоб дивились", dict(goal="express")), ("ні, сховати живіт", dict(goal="conceal", goal_zones=["belly"])),
        ("просто не хочу уваги", dict(goal="conceal")), ("сховати стегна", dict(goal="conceal", goal_zones=["hips"])),
        ("express без цитати", None)]
п = None
for слова, в in ходи:
    в = dict(в, quotes={к: слова for к in в}) if в else {"goal": "express"}
    п = хід(в, п, слова)
    print("  %-22s → мета %-10s зони %s" % (слова, п.get("мета"), п.get("мета_зони")))
