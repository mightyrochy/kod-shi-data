"""ПРИМ-1 (рядок 501): головний убір у приміщенні. Каталог_повний, образ [верх0, низ0, взуття0, ПЕРШИЙ головний убір
пулу]; сценарій — офіс, театр, парк і «місце не назване»; `формат` — приміщення / просто неба / не названо.
Друкує, яка знахідка про головний убір виходить (правило · регістр · сила_нп) — чи «нічого». Запуск із `джерела`:
PYTHONPATH=. python3 проби/прим1_убір.py"""
import json, sys; sys.path.insert(0, ".")
import feed as _Ф; _Ф.каталог_на_диску("каталог_повний.xml")
import bridge as B, pipeline as PL, composer as КМ, fit as ПС, colorspace as cs
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
бази = dict(вх["сценарій"], година=11, темп_c=18, опади="ні")
r = json.loads(B.виклик("запити", json.dumps(dict(вх, сценарій=dict(бази, нагода="робота", місце="офіс_креативний")), ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
к = r["кандидати"]; T = ПС.тіло(float(вх["зріст"]), {k: float(v) for k, v in вх["обхвати"].items()})
F = cs.features(cs.hx(вх["шкіра"]), cs.hx(вх["волосся"][0]), cs.hx(вх["очі"]))
убір = к.get("головний_убір") or [c for c in кат.values() if c.get("слот") == "головний_убір"]
осн = [dict(кат.get(к[с][0]["id"]) or к[с][0], слот=с) for с in ("верх", "низ", "взуття")]
import стенд_знімок as _S
for нагода, місце, формат in (("робота", "офіс_креативний", None), ("робота", "офіс_креативний", "приміщення"),
                              ("щоденне", "місто", "приміщення"), ("щоденне", "парк", "просто неба"),
                              ("щоденне", "місто", None)):
    сц = dict(бази, нагода=нагода, місце=місце)
    речі = [КМ._у_річ(dict(c), c["слот"], T) for c in осн + [dict(убір[0], слот="головний_убір")]]
    вих = PL.перевірити_образ(F, речі, тіло=T, формат=формат, **{k: v for k, v in сц.items() if k != "формат"})
    з = [z for _, z in _S._знахідки_рекурсивно(вих) if ("убір" in " ".join(map(str, z.get("речі") or [])) or "HAT" in str(z.get("правило")))
         and z.get("правило") not in ("K-HAT-01", "K-HAT-02")]      # ворота розміру голови — про інше, не про приміщення
    print("%-8s %-17s формат=%-12s → %s" % (нагода, місце, формат, "; ".join("%s·%s·%s" % (z.get("правило"), z.get("регістр"), z.get("сила_нп")) for z in з) or "нічого про убір у приміщенні"))
