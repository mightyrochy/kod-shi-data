"""Друкує, чи частковий вимір доходить до каталогу й палітри без вигаданої точки."""
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'прилади'))
from невизначеність_1993 import факти, суперечності_складових


def main():
    """П'ять відтворених випадків перевірки плюс інтервал тону."""
    import колір_річ as К
    import surface as П
    записи = факти()
    for з in записи:
        assert з['тон'] is None and з['точка'] is None and з['збагачення_точка'] is None, з
        assert з['палітра']['стан'] == 'невідомо' and з['палітра']['частки']['тон'] is None, з
        assert з['палітра']['роль'] != "акцент (сім'я твоїх очей)", з
        assert з['lab'] is None and з['межі'][0] == з['межі'][1] == з['сирі_осі'][0], з
        assert з['збагачення_межі'] == з['межі'], з
        assert not з['суд_палітри'] and з['суд_колір'] != 'виміряно з фото', з
        assert 'colour_partly_measured' in з['суд_свідок'] and not any(к.startswith('colour_word') for к in з['суд_свідок']), з
        assert 'colour_partly_measured' in з['суд_заяви'] and 'colour_unknown_not_checked' not in з['суд_заяви'], з
        assert len(з['картка_свідки']) == 1 and з['картка_свідки'][0]['values']['items'][0]['item_id'] == 'її-'+з['ключ'], з
        print(з['ключ'], 'точки нема; світлота й хрома збережені; палітра невідомо')
    сегмент = dict(lab=[60, 12, 0], хрома=[12, 3], тон=[350, 10], слово='рожевий')
    сегмент['колір_не_вимір'] = П.межі_сегмента(сегмент)
    assert К.точка_кольору(сегмент) is None and К.межі_кольору(сегмент) == (60, 60, 9, 15, (350, 10))
    print('інтервал через 0° збережено')
    с = суперечності_складових()
    assert с['світлота'] and с['хрома'] and с['узгоджений'] is None and с['тон'] == [None, None], с
    assert с['світлота']['сім_я_виміру'] is None, с
    print('невідомий тон не приховав суперечності відомої світлоти')


if __name__ == '__main__':
    main()
