"""5194: лічба конструкцій зі словами в сім'ях `формальність` і `траурний_регістр` тим самим способом, що
`шлях_слова_лічба.py` (іменовані конструкції верхнього рівня з ≥2 різними кириличними словами), але з розподілом:
А — закритий перелік кодів ядра (ключі паспорта, типи, слоти, коди візерунків) без фраз; Б/В — решта: слова
крамниці/назви/нагоди (Б) чи фрази, які пише код (В, рядок із пробілом). Список А — за назвою, з причиною.
Запуск: cd джерела && python3 проби/ошатність_5194_лічба.py"""
import ast, io, os, re
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); os.chdir(ТУТ)
А = {"ТИП_ІНТЕРВАЛ": "ключі — типи речі", "ТИПИ_СМУГА_З_ФОТО": "тип", "МІСЦЯ_ДІАПАЗОНИ": "ключі місць паспорта",
     "МІСЦЯ_ВЕЧІРНІ": "ключі місць", "МІСЦЯ_ДЕННІ": "ключі місць", "ВЕСІЛЬНІ_КЛЮЧІ": "ключі місць і нагод",
     "ТРАУР_ПЕРІОД": "мітки зв'язку: закритий перелік входу `траур` (коду в паспорті ще нема)",
     "ВЕЛИКІ_ПОВЕРХНІ_БІЛОГО": "слоти", "ПОВЕРХНІ_БІЛЯ_ОБЛИЧЧЯ_БІЛОГО": "слоти", "КОДИ_ТИП_ЗАБОРОНА": "типи",
     "КОДИ_ТИП_МУСИТЬ": "типи", "ВЕЛИКІ_ПОВЕРХНІ_ТРАУРУ": "слоти", "БІЛЯ_ОБЛИЧЧЯ_ТРАУРУ": "слоти",
     "МЕТАЛ_БІЛЯ_ОБЛИЧЧЯ_СЛОТИ": "слоти", "ТИПИ_МЕТАЛ_БІЛЯ_ОБЛИЧЧЯ": "типи", "ПРИКРАСИ_МЕТАЛ_ОБРАНО": "ключі металу паспорта",
     "ГУЧНІ_ВІЗЕРУНКИ_ТРАУРУ": "коди візерунка", "ПОЛЯ_ЗАЯВИ_ТРАУРУ": "імена полів паспорта"}
def рядки(в, з):
    if isinstance(в, ast.Constant) and isinstance(в.value, str): з.append(в.value)
    elif isinstance(в, ast.Call): [рядки(a, з) for a in в.args]
    elif isinstance(в, (ast.Tuple, ast.List, ast.Set)): [рядки(e, з) for e in в.elts]
    elif isinstance(в, ast.Dict): [рядки(x, з) for k, v in zip(в.keys, в.values) for x in ([k, v] if k else [v])]
разом = {"А": [], "Б/В": []}
for м in ("формальність", "траурний_регістр"):
    for в in ast.parse(io.open(м + ".py", encoding="utf-8").read()).body:
        if isinstance(в, (ast.Assign, ast.AnnAssign)) and isinstance(в.value, (ast.Dict, ast.List, ast.Tuple, ast.Set, ast.Call)):
            з = []; рядки(в.value, з)
            if len({w.lower() for t in з for w in re.findall(r"[а-яіїєґ]{3,}", t, re.I)}) >= 2:
                ім = (в.targets[0] if isinstance(в, ast.Assign) else в.target).id
                разом["А" if ім in А and not any(" " in t for t in з) else "Б/В"].append("%s.%s" % (м, ім))
print("конструкцій %d: А %d · Б/В %d" % (sum(map(len, разом.values())), len(разом["А"]), len(разом["Б/В"])))
print("Б/В: " + (", ".join(разом["Б/В"]) or "нема"))
