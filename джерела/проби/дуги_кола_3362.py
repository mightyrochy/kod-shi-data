"""КОЛІР-СХЕМИ (рядок 3362, крок (5) тіла #795): вердикт «тон речі в дузі» ДО → ПІСЛЯ на каталозі й пулі руки 1 (4 сцени стенда),
лише кольорові речі (`нейтраль_меж` «ні»). (1) Дуга сім'ї очей K-PAL-02/13: ДО — тон очей ±30° CIELAB, суд із запасом 10°
(`у_дугах_меж`); ПІСЛЯ — `palettes.дуга_очей` (±30° кола) зрізом `palettes.ПОРІГ_ОЧЕЙ` (`у_дугах_кола`); очі — стенд і ж1–ж9.
(2) Гіпотеза рядка 4780 — ролі схем (`палітра_схеми.СХЕМИ`, 12 якорів — центри секторів кола): дуга ролі ДО (CIELAB, суд K-PAL-03 із
запасом 10°) проти ±15° кола навколо того самого центру зрізом кінця згасання. Запуск із джерела/: python3 проби/дуги_кола_3362.py"""
import json, glob, sys, collections as K; sys.path.insert(0, ".")
import bridge as B, colorspace as cs, стенд_знімок as СЗ, колір_річ as КР, колір_відношення as КВ, palettes as ПЛ, палітра_схеми as ПС
вх0, пул, Л = json.load(open("стенд_вх.json", encoding="utf-8")), set(), K.Counter()
for назва in ("офіс·18°C", "дощ·ресторан·вечір", "весілля·гість", "спека·парк"):
    к = json.loads(B.виклик("запити", json.dumps(dict(вх0, сценарій=dict(СЗ.СЦЕНАРІЇ[назва]), випадок=назва), ensure_ascii=False)))["кандидати"]
    пул |= {r["id"] for xs in к.values() for r in xs}
кат = [r for r in B.каталог_останнього_пакета() if КР.межі_кольору(r) and КР.нейтраль_меж(r) == "ні"]
очі = [вх0["очі"]] + [json.load(open(f, encoding="utf-8"))["eyes"] for f in sorted(glob.glob("../аудит/проби/жінки/ж*.json"))]
б = lambda в: {"так": "т", "ні": "н"}.get(в, "?")
def лік(гр, x, до, після):
    вид = ("слово" if КР.не_вимір(x) else "вимір") + (" C<15" if КР.межі_кольору(x)[2] < 15 else " C≥15")
    for де in ("каталог",) + (("пул",) if x["id"] in пул else ()):
        Л[(гр, де, вид, б(до) + "→" + б(після))] += 1
for о in очі:
    h = cs.lch(cs.hx(о))[2]
    for x in кат:
        лік("(1) очі", x, КР.у_дугах_меж(x, [cs._arc(h, 30.0)], 10.0), КР.у_дугах_кола(x, [ПЛ.дуга_очей(h)], ПЛ.ПОРІГ_ОЧЕЙ))
for i in range(12):
    for сх, з in ПС.СХЕМИ.items():
        for д, роль in {tuple(д): р for р, д in з["тон"](cs.з_кола_художника(30.0 * i)).items() if isinstance(д, tuple)}.items():
            ц = (д[0] + ((д[1] - д[0]) % 360) / 2) % 360
            for x in кат:
                лік("(2) ролі", x, КР.у_дугах_меж(x, [д], 10.0), КР.у_дугах_кола(x, [cs.дуга_кола(ц, КВ.ДУГА_ВІДЛУННЯ)], КВ.КІНЕЦЬ_ЗГАСАННЯ))
print("кольорових речей каталогу %d, з них у пулі руки 1 — %d; очей %d" % (len(кат), sum(x["id"] in пул for x in кат), len(очі)))
for k, n in sorted(Л.items()): print("  %-9s %-8s %-11s %s %8d" % (*k, n))
