"""КОЛІР-СХЕМИ (рядок 3362, крок (5) тіла #795): вердикт «тон речі в дузі» ДО → ПІСЛЯ на каталозі й пулі руки 1 (4 сцени стенда),
лише кольорові речі (`нейтраль_меж` «ні»). (1) Дуга сім'ї очей K-PAL-02/13: ДО — тон очей ±30° CIELAB, суд із запасом 10°
(тверда дуга CIELAB, відтворена інлайн — `до_дуга`); ПІСЛЯ — `у_сім_ї_очей`: тон/підтон, хрома й світлота спільного кодування;
очі — стенд і ж1–ж9. (2) Ролі схем (рядок 4780; `палітра_схеми.СХЕМИ`, 12 якорів — центри секторів кола): ДО — дуга ролі ±пів CIELAB,
суд K-PAL-03 із запасом 10°; ПІСЛЯ — та сама дуга вікном із силою, що й суд (`у_дугах_кола` зрізом кінця згасання).
Запуск із джерела/: python3 проби/дуги_кола_3362.py"""
import json, glob, sys, collections as K; sys.path.insert(0, ".")
import bridge as B, colorspace as cs, стенд_знімок as СЗ, колір_річ as КР, палітра_схеми as ПС
вх0, пул, Л = json.load(open("стенд_вх.json", encoding="utf-8")), set(), K.Counter()
for назва in ("офіс·18°C", "дощ·ресторан·вечір", "весілля·гість", "спека·парк"):
    к = json.loads(B.виклик("запити", json.dumps(dict(вх0, сценарій=dict(СЗ.СЦЕНАРІЇ[назва]), випадок=назва), ensure_ascii=False)))["кандидати"]
    пул |= {r["id"] for xs in к.values() for r in xs}
кат = [r for r in B.каталог_останнього_пакета() if КР.межі_кольору(r) and КР.нейтраль_меж(r) == "ні"]
очі = [вх0["очі"]] + [json.load(open(f, encoding="utf-8"))["eyes"] for f in sorted(glob.glob("../аудит/проби/жінки/ж*.json"))]
б = lambda в: {"так": "т", "ні": "н"}.get(в, "?")
def до_дуга(x, д, запас):
    """Тверда дуга CIELAB із запасом, як `у_дугах_меж` до рядка 4780 (вимір — точкою, слово — дугою вікна)."""
    д = ((д[0] - запас) % 360, (д[1] + запас) % 360); м = КР.межі_кольору(x)
    if КР.не_вимір(x) is None: return "так" if КР._на_дузі(м[4][0] % 360, д) else "ні"
    if м[4] is None: return "невідомо"
    вл = {КР._на_дузі(h, д) for h in КР._тони_дуги((м[4][0] % 360, м[4][1] % 360), [д])}
    return "так" if вл == {True} else "ні" if вл == {False} else "невідомо"
def лік(гр, x, до, після):
    вид = ("слово" if КР.не_вимір(x) else "вимір") + (" C<15" if КР.межі_кольору(x)[2] < 15 else " C≥15")
    for де in ("каталог",) + (("пул",) if x["id"] in пул else ()):
        Л[(гр, де, вид, б(до) + "→" + б(після))] += 1
for о in очі:
    h = cs.lch(cs.hx(о))[2]; запис_очей = КР.запис_кольору(dict(lab=cs.hx(о)))
    for x in кат:
        лік("(1) очі", x, до_дуга(x, cs._arc(h, 30.0), 10.0), КР.у_сім_ї_очей(x, запис_очей))
for д in {д for i in range(12) for з in ПС.СХЕМИ.values() for д in з["тон"](cs.з_кола_художника(30.0 * i)).values() if isinstance(д, tuple)}:
    for x in кат:
        лік("(2) ролі", x, до_дуга(x, д, 10.0), КР.у_дугах_кола(x, [д], до_кінця_згасання=True))
print("кольорових речей каталогу %d, з них у пулі руки 1 — %d; очей %d" % (len(кат), sum(x["id"] in пул for x in кат), len(очі)))
for k, n in sorted(Л.items()): print("  %-9s %-8s %-11s %s %8d" % (*k, n))
