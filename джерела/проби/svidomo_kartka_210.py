# -*- coding: utf-8 -*-
"""Доповнення рядка 210: «сказавши СВІДОМО» на картці жінки. Рядок структурного
блокера служить ДВОМ читачам — моделі (промпт ремонту `_шапка_вибору`) і жінці
(`неповний` на картці), — і вказівка для моделі доїжджала до неї: «…лиши комплект
або візьми половину, СКАЗАВШИ СВІДОМО». «СВІДОМО» — назва поля протоколу (п.7:
машинних слів на екрані нема), і рядок не мав крапки, тож злипався з наступним
реченням картки («…сказавши СВІДОМО СВІДОМО Шари…»). ДО — `повнота_образу` з
origin/main, ПІСЛЯ — робоче дерево; ті самі суті блокерів із `суд_від_моделі`.
Запуск із теки `джерела`: PYTHONPATH=. python3 проби/svidomo_kartka_210.py"""
import re, subprocess, sys, types; sys.path.insert(0, ".")
import повнота_образу as ПІСЛЯ, суд_від_моделі as СМ
ДО = types.ModuleType("по_до"); ДО.__dict__["__name__"] = "по_до"
exec(subprocess.run(["git", "show", "origin/main:джерела/повнота_образу.py"],
                    capture_output=True, text=True).stdout, ДО.__dict__)
# суті беруться з живого коду, а не з рук: так проба не розійдеться з формулюванням
РЕЧІ = [dict(id="к-1", слот="комплект", назва="Костюм у смужку", тип="костюм"),
        dict(id="в-1", слот="верх", назва="Сорочка біла", тип="сорочка")]
СУТІ = СМ.структура_образу(РЕЧІ, сценарій=dict(нагода="робота", місце="офіс")) or []
print("блокерів від `структура_образу`: %d" % len(СУТІ))
МАШИНА = re.compile(r"СВІДОМО|\bSKU\b")
def рядок(м, суті):
    """Те саме, що модуль кладе в `неповний` на картку."""
    чис = getattr(м, "_без_вказівки_моделі", lambda x: str(x or ""))
    реч = getattr(м, "_реченням", lambda x: x)
    return реч("Образ неповний: " + "; ".join(x for x in (чис(с) for с in суті) if x))
д, п = рядок(ДО, СУТІ), рядок(ПІСЛЯ, СУТІ)
for мітка, р in (("ДО   ", д), ("ПІСЛЯ", п)):
    сл = МАШИНА.findall(р)
    print("%s %s" % (мітка, р))
    print("      машинних слів: %d %s · крапка в кінці: %s"
          % (len(сл), сл or "", "так" if р.rstrip().endswith(".") else "НІ"))
print("машинних слів на картці: ДО %d → ПІСЛЯ %d · злипання з наступним реченням: ДО %s → ПІСЛЯ %s"
      % (len(МАШИНА.findall(д)), len(МАШИНА.findall(п)),
         "так" if not д.rstrip().endswith(".") else "нема",
         "так" if not п.rstrip().endswith(".") else "нема"))
print("що сталось і що можна зробити — лишилось: %s"
      % ("так" if "подвоєння" in п and "лиши комплект" in п else "НІ"))
print("рядок МОДЕЛІ лишився з вказівкою (логіки промпта не чіпано): %s"
      % ("так" if any("сказавши СВІДОМО" in str(с) for с in СУТІ) else "НІ"))
