# -*- coding: utf-8 -*-
"""K-COL-03 (схеми за спаданням надійності) — ціле, перевірено пробою.

Корпус (тема-4:8226): «1 нейтральна база + акцент — найнадійніша і головний
генератор прісності; 2 тональна/монохромна (варіація фактур обовʼязкова);
3 аналогова; 4 приглушена комплементарна; 5 тріада — advanced. FORCE: default».
Правило ДІЄ В ДОБОРІ ПУЛУ, а не рядком у вердикті: `palette.СХЕМИ` тримає п'ять
схем у порядку корпусу, кожна роздає РОЛІ слотів, ДУГИ ТОНУ й смуги хроми;
`palette.розвилка` обирає одну, і далі дуга схеми — межа, яку `pipeline.схема_образу`
судить гейтом K-PAL-03. Проба стверджує весь ланцюг на живому пакеті.
Запуск із теки `джерела`: `python3 проби/col_K-COL-03.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import palette as PA, pipeline as PL

вх, r, кат, спец = ПВ.стенд(гілка=0)
схема = спец["схема"]
сл = спец["слоти"]
print("схем корпусу в коді: %d, у порядку надійності: %s" % (len(PA.СХЕМИ), ", ".join(PA.СХЕМИ)))
print("обрана для цієї людини: «%s» · ризик: %s" % (схема, PA.СХЕМИ[схема]["ризик"][:58]))
ролі = {k: (v.get("роль"), v.get("дуга_тону")) for k, v in сл.items()
        if isinstance(v, dict) and v.get("роль")}
for к in ("верх", "низ", "взуття"):
    if к in ролі: print("   %-8s роль %-10s дуга тону %s" % (к, ролі[к][0], ролі[к][1]))
# ДУГА СХЕМИ — МЕЖА: річ поза нею дістає гейт K-PAL-03 (запас 10°, той самий скрізь).
дуга = ролі["верх"][1]
чужа = ПВ.з_каталогу(кат, "верх", lambda L, C, h, _: (not PL._нейтральний_тон(h, C, L)
                                                      and abs((h - дуга[0]) % 360) > 60
                                                      and abs((дуга[1] - h) % 360) > 60))
ід = [чужа["id"]] + [x["id"] for с in ("низ", "взуття", "сумка") for x in (r["кандидати"].get(с) or [])[:1]]
зн, _ = ПВ.знахідки(вх, ід)
print("ФАКТ · річ поза дугою схеми «%s» (тон %.0f° проти %s): %s"
      % (схема, ПВ.lch(кат, чужа["id"])[2], дуга, ПВ.рядок(зн, "K-PAL-03")))
assert list(PA.СХЕМИ)[0] == "нейтрали+акцент" and list(PA.СХЕМИ)[-1] == "тріада", list(PA.СХЕМИ)
assert схема in PA.СХЕМИ and all(ролі[к][0] for к in ролі), (схема, ролі)
assert next((x for x in зн if x["правило"] == "K-PAL-03"), None), "дуга схеми не тримає межі"
