# -*- coding: utf-8 -*-
"""Н-V07-023: JSON паспорта провалився («модель мовчить») — досі це гасило
вето типів/тканин/принтів/кольорів мовчки (лише зони мали запасний шлях
чипами). Друкує, що впізнав `вето_поза_зонами_зі_слів` у чотирьох словниках
живого шляху, і скільки речей пакета блокує кожна вісь (до/після
`жорстке_ні_фільтр`). Запуск із теки `джерела`: python3 проби/pas_V07-023.py"""
import json, sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, pipeline as PL, profile as PR, feed as Ф

слова = "не ношу шкіру, леопард і рожеве, спідниці ніколи"
сц = dict(нагода="робота", місце="офіс", година=9, темп_c=18)
п = PL.паспорт_з_json("", сц, слова)          # текст моделі порожній: провал формату
print("помилка_формату=%r · вето=%s" % (п["помилка_формату"], п["вето"]))
assert п["вето"] == dict(типи=["спідниця"], тканини=["шкіра"], принти=["анімалістичний"],
                         кольори=["рожевий"], зони=[]), п["вето"]

д = B._застосувати_паспорт(dict(сценарій=dict(сц), паспорт=п))
print("жорстке_ні з паспорта:", д["жорстке_ні"])

вх = json.load(open("стенд_вх.json", encoding="utf-8"))
вх["каталог"], вх["гілка"] = Ф.каталог_на_диску("каталог_повний.xml"), 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()             # повний пакет ДО фільтра (для приладів)
осі = dict(типи="спідниця", тканини="шкіра", принти="анімалістичний", кольори="рожевий")
поле = dict(типи="тип", тканини="волокно", принти="візерунок", кольори="колір_назва")
for вісь, знач in осі.items():
    до = sum(1 for x in кат if x.get(поле[вісь]) == знач)
    print("%-8s «%s» у пакеті ДО фільтра: %d" % (вісь, знач, до))
_, відк = PR.жорстке_ні_фільтр(кат, д["жорстке_ні"])
print("пакет: до %d -> після %d (відкинуто %d)" % (len(кат), len(кат) - len(відк), len(відк)))
assert відк
# принт контрольованим прикладом: жива вибірка несе окрему, вже відому діру
# фіда («квітковий» замість «анімалістичний» на леопардових речах — інший наряд).
приклад = [dict(id=1, тип="сукня", візерунок="анімалістичний", назва="X"),
           dict(id=2, тип="сукня", візерунок="квітковий", назва="Y")]
лиш, _ = PR.жорстке_ні_фільтр(приклад, ["анімалістичний"])
print("принт контрольованим прикладом: лишилось %d з 2 (мусить бути 1)" % len(лиш))
assert len(лиш) == 1
