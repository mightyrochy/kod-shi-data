# -*- coding: utf-8 -*-
"""Рядок 48: чи повторюється сумка МІЖ РУКАМИ 1 і 2 одного прогону.

Та сама логіка, що `проби/vzuttia_руки.py` (PR #92 дав руці 2 власний сід
тільки-но для розв'язання нічиї — `bridge._сід_руки`, `СІЛЬ_РУКИ_2`), тут
прогнана на слоті «сумка»: сіль руки не слотоспецифічна (`сцен["сід"]` одне
число на весь пакет), тож або вона так само працює на сумках, або пул сумок
для цієї сцени занадто вузький, щоб перемішування рівних щось змінило.
Запуск: PYTHONPATH=. python3 проби/сумка_руки.py   (потрібен каталог_повний.xml)
"""
import sys, json, pathlib
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import bridge as B

вх = dict(json.load(open(_К / "стенд_вх.json", encoding="utf-8")),
          каталог=str(_К / "каталог_повний.xml"), гілка=0, варіантів=10,
          сценарій=dict(нагода="побачення", місце="ресторан", година=19, темп_c=20,
                        дрес_код="cocktail"),
          випадок="побачення, ресторан, 19:00, 20 °C")
для_K_VAR, останній = [], None
for сід in (4242, 17, 101):
    r = json.loads(B.виклик("запити", json.dumps(dict(вх, сід=сід), ensure_ascii=False)))
    а = [x["id"] for x in (r["кандидати"].get("сумка") or [])]
    б = [x["id"] for x in (r["кандидати_донора"].get("сумка") or [])]
    перетин10 = len(set(а[:10]) & set(б[:10]))
    print("сід %-5d сумка: пул %d (%d моделей рука1) / %d (%d моделей рука2) · "
          "перетин топ-10 рук 1∩2: %d із 10 (%d %%) · перший збігається: %s · "
          "перетин усього слота: %d"
          % (сід, len(а), len(set(а)), len(б), len(set(б)), перетин10, 10 * перетин10,
             (а[:1] == б[:1]), len(set(а) & set(б))))
    print("   рука 1 перші 5: %s" % ", ".join(x.split("@")[0] for x in а[:5]))
    print("   рука 2 перші 5: %s" % ", ".join(x.split("@")[0] for x in б[:5]))
    для_K_VAR.append((сід, а[0] if а else None, б[0] if б else None))
    останній = (сід, r)

повторів = sum(1 for _, п1, п2 in для_K_VAR if п1 and п1 == п2)
print("підсумок: перша сумка збіглась між руками на %d сідах із %d"
      % (повторів, len(для_K_VAR)))
