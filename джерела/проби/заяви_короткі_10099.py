"""Запис ж3 seed3_32: помилка довгого ключа; короткий дріт, чужий і повторений ключі.
Запуск: python -X utf8 проби/заяви_короткі_10099.py [seed3_32_мовний_шар.txt]."""
import json, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import мовний_шар as М

def проба():
    """Друкує зіставлення записаної відповіді та відповідь на короткий номер без моделі."""
    з = dict(code='selection_removed_item_from_stylist_look', values=dict(
        item=dict(free_text='Сукня оверсайз чорна', lang='uk'), item_id='ж-00348@wearme.ua'),
        recipient='woman', source='unknown', choice='code_rank', rank=None, item_ids=['ж-00348@wearme.ua'])
    р = М.розмітити_повідомлення({'рядок': dict(kind='card_added_by_selection', statements=[з])})
    ключ = р[0]['ключ']
    запис = '{"s_cbb83e93d17f5ecbd09ab67":"Я прибрала сукню оверсайз чорну з твого образу."}'
    if len(sys.argv) > 1:
        запис = pathlib.Path(sys.argv[1]).read_text(encoding='utf8').split('── ВІДПОВІДЬ', 1)[1].split('──\n', 1)[1]
    було = М.прийняти_повідомлення(р, запис)
    дріт = json.loads(М.промпт_повідомлень(р).split('ПОВІДОМЛЕННЯ:\n')[1])
    номер = дріт[0]['key']
    текст = 'Я прибрала сукню оверсайз чорну з твого образу.'
    є = М.прийняти_повідомлення(р, json.dumps({номер: текст}))
    чужий = М.прийняти_повідомлення(р, '{"999":"Чужий текст."}')
    дубль = М.прийняти_повідомлення(р, json.dumps({номер: текст})[:-1] + ', ' + json.dumps(номер) + ':"Інше."}')
    print('ключ входу:', ключ, '→ дріт:', номер, '· запис із помилкою без тексту:', len(було['без_відповіді']))
    print('відповідь за ключем запиту прийнята:', len(є['тексти']), '· чужа:', len(чужий['тексти']), '· повторена:', len(дубль['тексти']))
    assert було['без_відповіді'] == [ключ] and not чужий['тексти']
    if номер == '1':
        assert not дубль['тексти']
        assert є['тексти'] == {ключ: текст} and ключ not in М.промпт_повідомлень(р)
        багато = [dict(р[0], ключ=str(н)) for н in range(12)]
        assert len(М.прийняти_повідомлення(багато, '{"12":"Остання."}')['тексти']) == 1
        assert М.прийняти_повідомлення(багато[10:], '{"1":"Повтор."}')['тексти'] == {'10': 'Повтор.'}
        assert not М.прийняти_повідомлення(р, '{"1":"А."}\n{"1":"Б."}')['тексти']
    print('довжина ключа моделі:', len(номер), '· внутрішній ключ незмінний:', ключ == 's_cbb833e93d17f5ecbd09ab67')

if __name__ == '__main__':
    проба()
