"""ВОЛОССЯ-1 (рядок 1651): чи витрачає волосся бюджет хроми K-COL-02 — профілі ж1–ж8 і синтетичне неприродне.
Суд: `суд_від_моделі.бюджет_і_відлуння` (дві гучні речі + волосся); добір: `колір_хрома.бюджет_хроми` (лише волосся).
Друкує: hex, C*, h, чи волосся в K-COL-02 суду, чи волосся у знахідках бюджету.  Запуск із джерела/."""
import json, sys
sys.path.insert(0, "."); import colorspace as cs, суд_від_моделі as С, колір_хрома as КХ
def риси(hexes):
    return {k: dict(L=l, C=c, h=h) for k, (l, c, h) in
            zip(("волосся", "волосся_біля_обличчя"), (cs.lch(cs.hx(x)) for x in hexes))}
речі = [dict(id="a", слот="верх", hex="#c8102e", назва="a"), dict(id="b", слот="взуття", hex="#c8102e", назва="b")]
СИНТ = {"рожеве": "#e85aa0", "синє": "#2a5cc8", "зелене": "#2aa860", "фіолетове": "#7a3cc0", "вишневе": "#b3202a"}
набори = [("ж%d" % i, json.load(open("../аудит/проби/жінки/ж%d.json" % i))["hair"]) for i in range(1, 9)]
набори += [(n, [x]) for n, x in СИНТ.items()]
for n, hexes in набори:
    F = риси(hexes); f = max(F.values(), key=lambda f: f["C"])
    суд = [z for z in С.бюджет_і_відлуння(речі, F) if z["правило"] == "K-COL-02"]
    з_вол = sum("hair" in (z["заяви"][0]["values"].get("face") or ()) for z in суд)
    добір = [z for z in КХ.бюджет_хроми([], F) if any("волосся" in str(r) for r in z.get("речі") or ())]
    print("  %-10s %-8s C*%3.0f h%4.0f  суд K-COL-02 з волоссям: %d  добір (волосся): %s"
          % (n, hexes[0], f["C"], f["h"], з_вол, [(z["правило"], z["речі"]) for z in добір] or "—"))
