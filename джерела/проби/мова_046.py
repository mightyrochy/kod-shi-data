# -*- coding: utf-8 -*-
"""Т-07 (С-46): мовний вирок замикає петлю на кроці опису. До правки полів
`мова_повтор`, `промпт_мови`, `мова_рішення` не було, і `можна_видавати=False` не
тягнуло нічого: заборонена формула йшла жінці. Запуск із теки `джерела`:
`python3 проби/мова_046.py`."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, feed as Ф, pipeline as PL

вх = json.load(open("стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_brief.xml")
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
ід = [r["кандидати"][с][0]["id"] for с in list(r["кандидати"])[:3]]
БРУДНО = "Вільний крій подарує відчуття свободи в плечах."


def суд(текст, спроба):
    відп = json.dumps(dict(версія="1", текст=текст), ensure_ascii=False)
    return json.loads(B.виклик("від_моделі", json.dumps(
        dict(вх, ід=ід, текст_моделі=відп, відповідь="ОПИС_ВІДПОВІДЬ_V1",
             мова_спроба=спроба), ensure_ascii=False)))


for с in (1, PL.МОВНИХ_СПРОБ, PL.МОВНИХ_СПРОБ + 1):
    в = суд(БРУДНО, с)
    п, ріш = в.get("мова_повтор"), в.get("мова_рішення")
    assert в["мова"]["можна_видавати"] is False, в["мова"]
    assert ріш and ріш["спроб"] == с - 1 and ріш["правила"] == ["R-NVB-02"], ріш
    assert ріш["показувати_текст"] is True, "формулу вирішено показувати з позначкою"
    if с > PL.МОВНИХ_СПРОБ:
        assert not п, "спроби вичерпані, а перепис усе ще просять"
    else:
        assert п and п["спроба"] == с and п["порушення"][0]["натомість"], п
        assert "подарує відчуття свобод" in (в["промпт_мови"] or ""), в.get("промпт_мови")
        assert "R-NVB-02" not in в["промпт_мови"], "код правила поїхав моделі (Р-1)"
    print("спроба %d: перепис %s · Р-2 «%s» показувати_текст=%s"
          % (с, "просять" if п else "ні", ріш["рішення"], ріш["показувати_текст"]))
# ЯРУС РОСІЙСЬКОЇ — ІНШЕ РІШЕННЯ НА ТОМУ САМОМУ ШЛЯХУ (Р-2, 12.09)
р = суд("Жилет на голое тело.", PL.МОВНИХ_СПРОБ + 1)["мова_рішення"]
assert р["українська"] and р["показувати_текст"] is False, р
print("ярус російської: Р-2 «%s» показувати_текст=%s" % (р["рішення"], р["показувати_текст"]))
ч = суд("Лінія плеча збігається з твоєю; припуск у рукаві 4 см.", 1)
assert ч["мова"]["можна_видавати"] is True and not ч.get("мова_повтор") \
    and not ч.get("мова_рішення"), ч.get("мова")
print("чистий текст: циклу нема · ОК")
