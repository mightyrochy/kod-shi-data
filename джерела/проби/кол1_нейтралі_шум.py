# -*- coding: utf-8 -*-
"""КОЛ-1 (рядок 269): скільки «видимо різних» пар K-COL-06 є шумом кадру ОДНІЄЇ речі.

Вхід — `каталог_кадри.json.gz`, пари кадрів одного кольорового варіанта (той самий корінь імені,
що в `н4_друге_фото_de.py`), кадри-свідки (клас не з `НЕ_СВІДКИ`). Пара кадрів однієї речі —
ΔE_справжня = 0, тож кожне спрацювання тут — суд над шумом. Область правила: обидва кадри —
нейтралі (`колір_образу.нейтраль`), ΔL* < `step_min`. Друкує p95/p99 шуму в області, частку
спрацювань за порогом 6 (доти) і за 6 + `ΔE_шум_нейтралей` (після КОЛ-1).
Запуск із теки `джерела`: `python3 проби/кол1_нейтралі_шум.py`."""
import sys, pathlib, gzip, json, itertools, re
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import colorspace as CS, колір_образу as К
from реєстр_правил import C
from фід_кадр_колір import НЕ_СВІДКИ
корінь_файлу = lambda ф: re.sub(r"[_-]?\d+$", "", re.sub(r"_[0-9a-f]{8}-[0-9a-f-]{20,}$", "",
                                                            ф.rsplit("/", 1)[-1].rsplit(".", 1)[0]))

шум = []
for кадри in json.load(gzip.open(pathlib.Path(__file__).resolve().parent.parent / "каталог_кадри.json.gz",
                                 "rt", encoding="utf-8"))["записи"].values():
    гр = {}
    for к in кадри:
        if к.get("lab") and к.get("клас") not in НЕ_СВІДКИ:
            гр.setdefault(корінь_файлу(к["файл"]), []).append(tuple(к["lab"]))
    for g in гр.values():
        шум += [CS.de00(a, b) for a, b in itertools.combinations(g, 2)
                if К.нейтраль(a) and К.нейтраль(b) and abs(a[0] - b[0]) < C["step_min"]]
шум.sort()
q = lambda p: шум[min(len(шум) - 1, int(p * len(шум)))]
над = lambda т: 100.0 * sum(1 for x in шум if x > т) / len(шум)
print("ФАКТ · пар кадрів однієї речі в області K-COL-06: %d · шум ΔE00 медіана %.1f, p95 %.1f, p99 %.1f, макс %.1f"
      % (len(шум), q(.5), q(.95), q(.99), шум[-1]))
print("ФАКТ · «видимо різні» над шумом однієї речі: поріг 6.0 — %.1f %%; поріг 6.0 + %.1f — %.2f %%"
      % (над(6.0), C["ΔE_шум_нейтралей"], над(6.0 + C["ΔE_шум_нейтралей"])))
