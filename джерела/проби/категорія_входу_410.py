# -*- coding: utf-8 -*-
# РЗ-410. ФАКТ: чи несе вхід розбору (`каталог_розбір.вхід`) рубрику жниварки `offer["категорія"]`,
# скільки речей мають її суперечну слоту продукту, і хто правий про слот на еталоні (правда з фото).
import os, sys, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed, каталог_розбір as К
офери = feed.читати_yml(feed.каталог_на_диску())[0]
ПІДТИП = {"браслет", "сережки", "намисто", "каблучка", "брошка", "підвіска", "прикраси"}
вхід_із = lambda o: json.dumps(К.вхід(o), ensure_ascii=False)
в_ключі = sum(1 for o in офери if "category" in К.вхід(o) or "категорія" in К.вхід(o))
в_тексті = sum(1 for o in офери if o["категорія"] and "\"%s\"" % o["категорія"] in вхід_із(o))
супер = [o for o in офери if o["категорія"] != feed.слот(o)
         and not (o["категорія"] == "прикраси" and feed.слот(o) in ПІДТИП)]
print("речей %d · ключ «категорія» у вході %d · рубрика жниварки окремим значенням у вході %d"
      % (len(офери), в_ключі, в_тексті))
print("рубрика ≠ слот продукту (без прикрас-підтипів) %d; з них вхід несе цю рубрику %d"
      % (len(супер), sum(1 for o in супер if "\"%s\"" % o["категорія"] in вхід_із(o))))
по_id = {o["id"]: o for o in офери}
е = json.load(open(os.path.join(os.path.dirname(__file__), "еталон_розбору.json"), encoding="utf-8"))["речі"]
п = [(по_id[r["id"]], r["правда"]["slot"]) for r in е if r["id"] in по_id and isinstance(r["правда"]["slot"], list)]
Є = {"сукня": "dress", "верх": "top", "низ": "bottom", "верхній_шар": "outerwear", "взуття": "shoes",
     "сумка": "bag", "пояс": "belt", "комплект": "set"}
print("еталон: речей зі слотом-правдою %d · рубрика права %d · слот продукту правий %d"
      % (len(п), sum(1 for o, пр in п if Є.get(o["категорія"], o["категорія"]) in пр),
         sum(1 for o, пр in п if Є.get(feed.слот(o), feed.слот(o)) in пр)))
