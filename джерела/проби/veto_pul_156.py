# -*- coding: utf-8 -*-
"""ПУЛ ПРОТИ ПРОХАННЯ (рядок 156, друга проба). Гейт «прохання — не вето» стояв на
шві (`жорстке_ні`, бриф, рядки для жінки), а ДОБІР брав сире вето моделі: на стенді
при вето [блейзер, куртка] діагноз казав «відсічено до пулу: вето людини: блейзер 98,
вето людини: куртка 84», тоді як екран уже казав «без: темні кольори». Проба міряє
той самий шлях, що й прогін (`bridge.запити` → `відсічено.лічба`): скільки речей
кожного слова вето знято з пулу ДО (сире вето) і ПІСЛЯ (чинні межі).
Запуск: cd джерела && python3 проби/veto_pul_156.py"""
import json, re, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B, feed as Ф, pipeline as PL

ІР = "для авто та на урок, надворі дощ. Можна яскравий верх — куртку чи жакет, не темного кольору"
КОНТРОЛЬ = "у суботу прогулянка в парку, +14. Не ношу куртки, краще пальто чи тренч"
ВИПАДКИ = [("Ір (просила куртку й жакет)", ІР, ["блейзер", "куртка"], ["темні кольори"], []),
           ("контроль (просила пальто й тренч)", КОНТРОЛЬ, ["куртка", "пальто", "тренч"], [], ["куртка"])]
база = json.load(open("стенд_вх.json", encoding="utf-8"))
каталог = Ф.каталог_на_диску()
впало = 0
for назва, слова, типи, кольори, чинні in ВИПАДКИ:
    п = dict(слова=слова, нагода="щоденне", місце="надворі", година=12, темп_c=14, опади="ні",
             намір="conventional", вето=dict(типи=типи, тканини=[], принти=[], кольори=кольори, зони=[]))
    # ДО — те, що робив код до правки: у добір їде СИРЕ вето моделі
    for мітка, вето in (("ДО   ", dict(п["вето"])), ("ПІСЛЯ", PL.вето_чинне(п))):
        вх = dict(база, каталог=каталог, варіантів=1, гілка=0, сід=3, вимоги=слова,
                  паспорт=dict(п, вето_тверде=вето))
        r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
        л = {k: v for k, v in (((r.get("відсічено") or {}).get("лічба")) or {}).items()
             if k.startswith("вето людини")}
        пул = sum(len(v) for v in (r.get("кандидати") or {}).values())
        print("%-34s %s · пул %d · знято вето людини: %s"
              % (назва if мітка.strip() == "ДО" else "", мітка, пул,
                 json.dumps(л, ensure_ascii=False) if л else "нічого"))
        if мітка.strip() == "ПІСЛЯ":
            зайве = [k for k in л if not any(re.search(re.escape(c[:max(4, len(c) - 2)]), k, re.I) for c in чинні)]
            if зайве:
                впало += 1; print("     ✗ знято те, чого вона просила: %s" % зайве)
assert not впало, "пул досі ріже прохання"
