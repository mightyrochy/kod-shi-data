"""Записані профілі: непідтверджений підтон не стає класом, а її відповідь працює без фото."""
import json, pathlib, sys
К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(К))
import міст_вхід as М, palette as П, пакет_моделі as ПМ


def main():
    """Звіряє утримання, дріт моделі й елісітацію за різного походження кольору."""
    база = json.loads((К / "стенд_вх.json").read_text("utf8"))
    профілі = sorted((К.parent / "аудит/проби/жінки").glob("*.json"))
    assert профілі, "нема записаних профілів"
    помилки = []; випадків = 0
    for шлях in профілі:
        ж = json.loads(шлях.read_text("utf8"))
        for дж in ("model_hex", "uncontrolled"):
            F = М.features(dict(база, шкіра=ж["skin"], волосся=ж["hair"], очі=ж["eyes"], source=дж))[0]
            for стан in (F, {к: в for к, в in F.items() if к != "шкіра"}):
                for слова in ({}, {"метал": "срібло"}, {"метал": "не знаю"}):
                    т = П.температура(стан, самозвіт=слова)
                    якір = П.нейтраль_якір(стан, драп=слова, слот="верх")
                    дріт = ПМ.людина_для_пакета(None, {"температура": т})["температура"]
                    є = слова.get("метал") == "срібло"
                    правильно = (т.get("клас") == "холодна" and т.get("метал") == "срібло"
                                  and т.get("впорскувати_в_запит") and дріт["джерело"] == "самозвіт") if є else (
                                  т.get("клас") == "не_стверджується" and not т.get("придатно")
                                  and т.get("метал") is None and т.get("нейтраль_дуга") is None
                                  and not т.get("впорскувати_в_запит") and дріт["клас"] == "не_стверджується")
                    правильно = правильно and (якір.get("тепло_особи", 0) < 0 if є else not якір.get("вага_вікна"))
                    if not правильно: помилки.append([шлях.stem, дж, "шкіра" in стан, слова, т.get("клас")])
                    випадків += 1
    print(json.dumps(dict(випадків=випадків, порушень=len(помилки), приклади=помилки[:8]), ensure_ascii=False))
    return bool(помилки)


if __name__ == "__main__":
    sys.exit(main())
