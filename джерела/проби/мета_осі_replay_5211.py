"""Рядок 5211: replay записаних паспортів зі старою `мета` → дві осі (`паспорт_нагоди.мета_на_осі`) без втрат.
Друкує: скільки паспортів, розклад старих мет і чи збігається дія старого запису з новою: вісь уваги для
кольору й форми («вище» діяла як «лестити»), прапор «довша лінія», суд зони R-CHEV-08."""
import glob, json, os, sys, collections
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import паспорт_нагоди as ПН, регістр_уваги as РУ
корінь = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
def паспорти(в):
    if isinstance(в, dict):
        if "мета" in в and ("нагода" in в or "подія" in в) and "мета_важливо" not in в:
            yield в
        for x in в.values(): yield from паспорти(x)
    elif isinstance(в, list):
        for x in в: yield from паспорти(x)
def старе(п):   # як читав код до 15.10: увага всього образу, «вище», чи судиться зона
    м, з = п.get("мета"), set(п.get("мета_зони") or ()) & set(РУ.ЗОНА_МЕТИ_СЛОТИ)
    уваги = None if (м == "приховати" and з) or м in (None, "невідомо") else м
    return ("лестити" if уваги == "вище" else уваги, м == "вище", bool(з) and м == "приховати")
def нове(п):
    м = None if п.get("мета") in (None, "невідомо") else п["мета"]
    return (м, "вище" in п["мета_важливо"], bool(РУ.відомі_зони(п.get("мета_зони"))))
файли, розклад, розбіжні = 0, collections.Counter(), []
for ф in glob.glob(os.path.join(корінь, "**", "*.json"), recursive=True):
    if "node_modules" in ф: continue
    try: д = json.load(open(ф, encoding="utf-8"))
    except Exception: continue
    for п in паспорти(д):
        файли += 1; розклад[(п.get("мета"), bool(п.get("мета_зони")))] += 1
        н = ПН.мета_на_осі(п)
        if старе(п) != нове(н): розбіжні.append((os.path.basename(ф), старе(п), нове(н)))
print("записаних паспортів зі старою «мета»: %d; (мета, зони) → %s" % (файли, dict(розклад)))
for п in ({"мета": "вище", "нагода": "x"}, {"мета": "приховати", "мета_зони": ["живіт"], "нагода": "x"},
          {"мета": "експресія", "нагода": "x"}, {"мета": "приховати", "нагода": "x"}):
    н = ПН.мета_на_осі(п); print("  %s → %s" % (п, {к: н.get(к) for к in ("мета", "мета_важливо", "мета_зони")}),
                               "дія та сама" if старе(п) == нове(н) else "ДІЯ ЗМІНИЛАСЬ")
print("розбіжних дій на записах: %d %s" % (len(розбіжні), розбіжні[:3]))
