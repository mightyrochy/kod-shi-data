# -*- coding: utf-8 -*-
"""Промпт опису рук 1–2 до/після П-2 на сирих прогонах ноутбука (ОПИС_V1 → ОПИС_ВІДПОВІДЬ_V1).

Той самий обʼєкт опису (старий промпт без `завдання`) крізь `розбір_відповідей.промпт_опису`
(оголошення `ОПИС` англійською, дані `дріт_моделі.опис`): символи й токени gemma
(GEMMA_TOKENIZER) старого й нового і загублені факти. Адреса фото («фото») не йде й на main
до П-2: зображення стоять перед обʼєктом блоками, чиє котре — «photos». Слот речі — свідомо
(`дріт_факти.СВІДОМО`). Мова вільного тексту — English (з мовним шаром показу).
Запуск: cd джерела && GEMMA_TOKENIZER=… python3 проби/промпт_опису.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import дріт_факти as Ф, розбір_відповідей as Р
разом = [0, 0]
for ім, п in Ф.сирі("*ОПИС_V1_ОПИС_ВІДПОВІДЬ_V1*"):
    ст = json.loads(п)
    об = dict({к: v for к, v in ст.items() if к != "завдання"},
              завдання={"мова": "English", "відповідь": "ОПИС_ВІДПОВІДЬ_V1"})
    н = json.dumps(Р.промпт_опису(об), ensure_ascii=False, separators=(",", ":"))
    без = Ф.загублено(ст, н, ще=("фото",))
    разом[0] += 1; разом[1] += len(без)
    print("%-44s було %5d симв / %4s ток → стало %5d симв / %4s ток · загублено: %s"
          % (ім[:44], len(п), Ф.ток(п), len(н), Ф.ток(н), без[:6] or "нічого"))
print("прогонів %d, загублених фактів разом %d" % tuple(разом))
