"""Рядки 472, 1434: назва місця поза плитками — словами мовної моделі (`place_words` → `місце_слова`), не ключем.
Друкує по ходах: місце паспорта, слова при ньому, і чи поле стоїть у словнику ходу розмови. Запуск із `джерела`."""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import мовний_шар as МШ
п = lambda код, цит: {"quote": цит, "value": код}
ХОДИ = [("церква + слова", {"occasion": п("church", "на службу в церкву"), "place": п("church_service", "на службу в церкву"),
                            "place_words": "Церква, служба"}, "У неділю йду на службу в церкву"),
        ("хід без місця", {"hour": п(9, "о 9")}, "о 9 ранку"),
        ("нове місце без слів", {"place": п("funeral", "на похорон")}, "ні, це на похорон"),
        ("слова без місця", {"place_words": "Школа"}, "в школі"),
        ("випускний", {"place": п("school_parents_meeting", "у школі сина"), "place_words": "Школа, випускний сина"},
         "на випускний у школі сина")]
досі, с = {}, {}
for назва, в, слова in ХОДИ:
    вн = МШ.прийняти_розмову(json.dumps({"update": в, "need": "none", "text": "ок"}))["внутрішня"]
    досі = МШ.паспорт_з_шару(вн, с, None, досі, слова_ходу=[слова])["паспорт"]
    if назва == "слова без місця":
        досі = dict(досі, місце=None, місце_слова=None)
        досі = МШ.паспорт_з_шару(вн, с, None, досі, слова_ходу=[слова])["паспорт"]
    print("%-20s місце=%-20s місце_слова=%s" % (назва, досі.get("місце"), досі.get("місце_слова")))
print("place_words у словнику ходу:", any(р.startswith("- place_words —") for р in МШ._коди_розмови()))
