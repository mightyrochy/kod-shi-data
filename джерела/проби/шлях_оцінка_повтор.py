"""Ділянка 8: ЧОМУ ПУНКТИ ПОВТОРЮЮТЬСЯ НА ДРУГОМУ ХОДІ. Код щоходу кладе в «паспорт_досі»
вердикт коду над КОЖНОЮ її річчю і просить модель переказувати його; позначки «це вже сказано»
нема. Міряє розмір цього блока в промпті ходу 2 і показує, що рядки коду на другому ході
мовчать (`оцінитиРечіЗФотоП` друкує лише зміну). Запуск: python3 проби/шлях_оцінка_повтор.py"""
import sys, json, re; sys.path.insert(0, '.')
import паспорт_нагоди as ПН, річ_з_фото as РФ, colorspace as cs
from міст_вхід import _збірка, _нормалізувати_вхід
вх = json.load(open('стенд_вх.json')); F, T, _з, _к = _збірка(_нормалізувати_вхід(dict(вх)))
СЦЕН = dict(нагода='щоденне', місце='зал', година=11, темп_c=18)
ОБРАЗ = [('ф1', 'жакет приталений', 'верхній_шар', '#7d7f63', 'хакі'),
         ('ф2', 'сорочка з драпуванням', 'верх', '#cfd8e3', 'блакитний'),
         ('ф3', 'шкіряна міні-спідниця трапеція', 'низ', '#6b1f2a', 'бордовий'),
         ('ф4', 'клатч плетіння', 'сумка', '#7a2230', 'бордовий'),
         ('ф5', 'ботильйони на підборах', 'взуття', '#e6dfd2', 'вершковий')]
речі = []
for і, н, с, h, к in ОБРАЗ:
    р = dict(ід=і, фото=і, назва=н, слот=с, колір=к, ошатність=6, чия='моя', закріплена=True,
             вимір=dict(lab=list(cs.hx(h)), hex=h, слово=к))
    р['вердикт'] = РФ.вердикт(р, F, T, СЦЕН, типова_нагода=True)
    речі.append(р)
пасп = dict(нагода='щоденне', місце='зал', речі_з_фото=речі,
            джерело_полів={'нагода': ПН.ТИПОВА_НАГОДА_РЕЧІ})
для_моделі = [РФ.для_моделі(р) for р in речі]
блок = json.dumps(для_моделі, ensure_ascii=False)
вердикти = sum(len(р.get('вердикт_коду') or '') for р in для_моделі)
print('речей у «паспорт_досі.речі_з_фото»: %d; блок %d симв., із них «вердикт_коду» %d симв.'
      % (len(для_моделі), len(блок), вердикти))
print('полів «вже сказано жінці» / «не повторювати» в записі речі: %d (поля: %s)'
      % (sum(1 for k in для_моделі[0] if 'сказ' in k or 'повтор' in k), ', '.join(для_моделі[0])))
_пн = open('паспорт_нагоди.py', encoding='utf-8').read()
print('паспорт_нагоди.py:%d — промпт просить: «"вердикт_коду" її речей переказуй своїми словами»'
      % (_пн[:_пн.index('переказуй своїми словами')].count('\n') + 1))
хід2 = ПН.промпт_паспорта(СЦЕН, 'Мене цікавить просто наскільки вдало ці кольори поєднуються',
                          паспорт=пасп, історія=[{'хто': 'людина', 'текст': '[фото ф1] …'}])
print('промпт ходу 2: %d симв., із них блок її речей %d (%.0f %%)'
      % (len(хід2), len(блок), 100.0 * len(блок) / len(хід2)))
ПОКАЗ = open('показ.html', encoding='utf-8').read()
print('показ.html:%d — «if (стало && стало !== було)»: рядок коду друкується лише коли вердикт'
      ' ЗМІНИВСЯ, тож на ході 2 код мовчить, а модель переказує ті самі п\'ять вердиктів заново'
      % (ПОКАЗ[:ПОКАЗ.index('if (стало && стало !== було)')].count('\n') + 1))
