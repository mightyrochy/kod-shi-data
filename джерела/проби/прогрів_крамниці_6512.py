"""Рядок 6512: крамниця картки без нагоди бере записи каталогу з бази (`оцінка_образу._каталог_без_пулу_кроками`), а не з
пакета пулу (`міст_пакет.пакет_каталогу`), — без специфікацій вікон і покриття каталогу. Друкує, чи ті самі записи (усі
поля, той самий порядок) і ті самі кандидати слотів, і час кожного шляху (з нагодою крамниця бере той самий пакет із
кеша). Запуск із `джерела`: python3 проби/прогрів_крамниці_6512.py"""
import sys, json, time; sys.path.insert(0, '.')
import оцінка_образу as О, міст_пакет as МП, міст_основи as МО
from міст_вхід import збірка as _збірка
вх = json.load(open('стенд_вх.json'))
for назва, екран in (("нічого не названо", {}), ("лише +18 °C", {"темп_c": 18}), ("нагода «робота»", {"нагода": "робота"})):
    F, T, dd = О.профіль(dict(вх, сценарій_оцінки=екран))
    сц, _ = О.сценарій_оцінки(екран)
    сцен, _ = О._сцена(сц, dd)
    д = dict(dd, сценарій={к: v for к, v in сцен.items() if к in ("нагода", "місце", "дрес_код", "темп_c", "опади", "година", "пора")})
    д.pop("паспорт", None)
    F2, T2, зріст, kw = _збірка(д)
    п, гілка, _с, _п = МО.пакет_гілки(д, F2, T2, зріст, kw, None, д.get("намір") or "conventional")
    МП.КЕШ_ПАКЕТА.clear()
    т = time.time()
    пак = МП.пакет_каталогу(д, F2, T2, п, 0 if гілка is None else гілка, за_замовчуванням=(гілка is None))
    т_пулу = time.time() - т
    О._КЕШ_БЕЗ_ПУЛУ.clear()
    т = time.time()
    пули, чому, готовий, _пак = О._крамниця(dd, F, T, сцен, ["верх", "низ", "взуття"])
    т_нове = time.time() - т
    if пак.get("готово") and пак.get("кандидати"):
        старі = {с: list(пак["кандидати"].get(с) or []) for с in пули}
    else:
        старі = {с: [r for r in (пак.get("_каталог") or []) if r.get("слот") == с] for с in пули}
    той_самий = старі == пули and (пак.get("чому") or "пулу нема") == (чому or "пулу нема") and bool(готовий) == bool(
        пак.get("готово") and пак.get("кандидати"))
    print("  %-18s пул: %-5s кандидатів %s · ті самі записи й причина: %s · пакет пулу %.1f с, крамниця тепер %.1f с" % (
          назва, bool(готовий), json.dumps({с: len(р) for с, р in пули.items()}, ensure_ascii=False), той_самий, т_пулу, т_нове))
    assert той_самий, "крамниця дала інші записи, ніж пакет пулу (%s)" % назва
print("→ без нагоди крамниця бере ті самі записи каталогу без специфікацій і покриття вікон; з нагодою — пул, як доти.")
