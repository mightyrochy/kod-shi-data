"""Т-7 · номер, якого в пулі нема («#999·77» — поза нумерацією; справжній номер із чужим кодом магазину), в образі,
де решта речей справжні. Образ іде в суд без цієї речі — чи лишається про неї запис у відповіді мосту (а з нею —
у звіті власника, `етапи.виклики[].розбір_блоків`)? Пул — рука 1 пакета `стенд_вх.json`; третій образ — без
вигаданого, останнім (верхній рівень відповіді — вердикт останнього образу). Друкує факт.
Запуск: cd джерела && python3 проби/номери_вигадані_т7.py"""
import json, os, sys
Д = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, Д); os.chdir(Д)
import bridge as B
вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["гілка"] = 0
пул = json.loads(json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["руки"]["1"])["пул"]
речі = [пул[с][0]["н"] for с in ("верх", "низ", "взуття", "сумка") if пул.get(с)]
н0, к0 = речі[0][1:].split("·")
чужий = "#%s·%02d" % (н0, (int(к0) + 1) % 100)
ВИГАДАНІ = (("о1", "#999·77"), ("о2", чужий))
відп = {"версія": "1", "образи": [{"ід": "о1", "підпис": "перший", "речі": речі + ["#999·77"]},
                                  {"ід": "о2", "підпис": "другий", "речі": речі[1:] + [чужий]},
                                  {"ід": "о3", "підпис": "третій", "речі": речі}]}
в = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=json.dumps(відп, ensure_ascii=False)),
                                                 ensure_ascii=False)))
print("ФАКТ · образів у суді: %d з 3 · речей у них: %s" % (len(в.get("образи") or []),
                                                         [len(о.get("ід") or []) for о in в.get("образи") or []]))
for о, н in ВИГАДАНІ:
    де = [к for к, v in в.items() if н in json.dumps(v, ensure_ascii=False)]
    print("ФАКТ · %s в образі %s — названо в полях відповіді мосту: %s" % (н, о, ", ".join(де) or "ніде"))
print("ФАКТ · розбір_блоків.невідомі_в_образах: %s" % json.dumps(
    (в.get("розбір_блоків") or {}).get("невідомі_в_образах", "поля нема"), ensure_ascii=False))
