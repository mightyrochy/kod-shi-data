# -*- coding: utf-8 -*-
"""Адреси опор ремонту: резервування ід, дублі, половини комплекту й записи суду."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import selection_policy as П
import вердикт_моделі as В

о = lambda ід, речі: dict(ід=ід, речі=речі)
сцени = [
    ("адреса пізнішого образу зарезервована", [о("новий", ["a"]), о("о1", ["a"])],
     [о("о1", ["a"]), о("о2", ["a", "b"])], [1, 0]),
    ("один старий не дублюється", [о("x", ["a"]), о("y", ["a"])], [о("о1", ["a"])], [0, None]),
    ("порожній ід не зводить чужі образи", [о("", ["b"])], [о("", ["a"])], [None]),
    ("дубль ід зіставляється складом", [о("о1", ["b"]), о("о1", ["a"])],
     [о("о1", ["a"]), о("о2", ["b"])], [1, 0]),
    ("половини комплекту", [о("новий", ["#1·00/top"])], [о("о1", ["#1·00/bottom"])], [0]),
    ("запис суду має номер образу", [dict(ід=["каталог-a"], номер="о2", речі=[dict(id="каталог-a")],
                                      речі_н=["#1·00"])], [о("о1", ["#1·00"]), о("о2", ["#9·00"])], [1]),
    ("немає старих", [о("о1", ["a"])], [], [None]),
    ("немає нових", [], [о("о1", ["a"])], []),
]
вад = 0
for назва, нові, старі, очік in сцени:
    факт = П.пари_ремонту(нові, старі)
    вад += факт != очік
    print(назва, "·", факт, "·", факт == очік)
поп = dict(образи=[dict(о("о1", ["a"]), опори=[dict(правило="K-ACC-01")])])
нові = [о("x", ["a"]), о("y", ["a"])]
утр = В.утрачені_опори(нові, поп)
ок = [len(у) for у in утр] == [1, 0] and not В.опори_зниклих_образів(нові, поп)
вад += not ок
print("опора не приписана двом образам ·", ок, "· вад:", вад)
sys.exit(bool(вад))
