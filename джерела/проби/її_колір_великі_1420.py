# -*- coding: utf-8 -*-
"""Рядок 1420 (ЇЇ-ВИБІР): чи бажаний колір без слота («хочу щось червоне») дає великі речі цього кольору в пулі.
Той самий вхід стенда, нагода «побачення» вдень, паспорт із бажанням `{"колір": "червоний"}` (як ж1_побачення_день_червоне).
Друкує по великих слотах пулу руки 1: скільки речей названого кольору (за назвою чи полем кольору) і скільки — за бажанням.
Запуск: cd джерела && python3 проби/її_колір_великі_1420.py [червоний]"""
import json, os, sys
Д = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, Д); os.chdir(Д)
import bridge as B, feed, різноманітність_пулу as R
feed.каталог_на_диску()
КОЛІР = sys.argv[1] if len(sys.argv) > 1 else "червоний"
вх = json.load(open("стенд_вх.json"))
вх["сценарій"] = dict(нагода="побачення", година=13, темп_c=18)
вх["паспорт"] = {"бажання_коди": [{"колір": КОЛІР, "фраза": КОЛІР}], "бажання": [КОЛІР]}
р = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
пул = р["пакети"]["1"]["пул"]
осн = R._основи({"колір": КОЛІР})[0]
усього = sum(len(v) for v in пул.values())
великі = [с for с in ("верх", "низ", "сукня", "комплект", "верхній_шар") if с in пул]
for с in великі:
    її = [x for x in пул[с] if осн in (str(x.get("назва")) + " " + str(x.get("колір"))).lower()]
    print("ФАКТ · %s: %d з %d речей «%s» · за бажанням %d · %s" % (
        с, len(її), len(пул[с]), КОЛІР, sum(1 for x in її if x.get("за_бажанням")),
        "; ".join(str(x.get("назва"))[:40] for x in її[:3])))
print("ФАКТ · пул руки 1: %d речей; великих «%s» — %d" % (усього, КОЛІР, sum(
    1 for с in великі for x in пул[с] if осн in (str(x.get("назва")) + " " + str(x.get("колір"))).lower())))
