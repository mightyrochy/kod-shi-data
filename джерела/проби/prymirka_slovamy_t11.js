/* Т-11: річ образу БЕЗ ФОТО — у промпті картинки і в підписі під кадром.
   Прогін тестувальниці (ComfyUI, сід 13, «Ір, собаки», `seed13_16_ПРИМІРЯННЯ.txt`):
   промпт перелічував самі лише фото крамниць, а про її «світлі джинси кльош» слова не
   було; підпис тим часом обіцяв «Без фото малювались: світлі джинси кльош». На кадрах —
   голі коліна (`p4_kadr_ruka2_bez_dzhynsiv_seed13.jpg`) і спідниця замість джинсів.
   Її річ будується тим самим кодом, що в прогоні: її слова → паспорт → картка.
   Запуск із теки `джерела`: node проби/prymirka_slovamy_t11.js */
const fs = require("fs"), { execFileSync } = require("child_process");
const ПИТОН = `import json, річ_з_фото as Р
д = Р.речі_словами('гуляю з собаками в парку, у мене є світлі джинси кльош')
print(json.dumps([Р.картка(Р.запис_каталогу(р)) for р in Р.речі_з_json([], словами=д)], ensure_ascii=False))`;
const її = JSON.parse(execFileSync("python3", ["-c", ПИТОН], { encoding: "utf8", cwd: __dirname + "/.." }));
/* Образ руки 1 того прогону: чотири речі крамниць зі знімками, її джинси без фото і
   п'ята річ крамниці, чийого знімка фід не дав (та сама гілка «без фото»). */
const ЗФОТО = [["взуття", "Черевики Жокейки"], ["сумка", "Сумка Welfare"], ["верх", "Светр-кейп"],
               ["верхній_шар", "Кардиган максі"]].map(([слот, назва]) => ({ слот, назва, фото: "https://i/x.jpg" }));
const БЕЗ = її.concat([{ слот: "прикраса", назва: "Підвіска", колір: "срібний" }]);
const тіло = (html, рег, мітка) => {
  const m = html.match(рег);
  if (!m) throw new Error("не знайдено " + рег + " у " + мітка);
  return new Function("зФото", "свої", "return (" + m[0].replace(/^const [^=]+= /, "").replace(/;$/, "") + ");");
};
const main = execFileSync("git", ["show", "origin/main:джерела/показ.html"], { encoding: "utf8" });
const тут = fs.readFileSync(__dirname + "/../показ.html", "utf8");
/* ДО: перелік складався інлайн у `приміряти` — самі фото. ПІСЛЯ: два іменовані вирази. */
const доСписок = тіло(main, /const список = зФото[\s\S]*?join\('\\n'\);/, "origin/main")(ЗФОТО, []);
const словами = тіло(тут, /const речі_словами_П = [\s\S]*?\n}\);/, "робоче дерево")()(БЕЗ);
const післяСписок = тіло(тут, /const перелік_речей_П = [\s\S]*?\n     : ''\);/, "робоче дерево")()(ЗФОТО, словами);
const усі = (текст, імена) => імена.length > 0 && імена.every(н => текст.includes(н));
for (const [мітка, промпт, підпис] of [["ДО (origin/main)", доСписок, БЕЗ.map(р => р.назва)],
                                       ["ПІСЛЯ (робоче дерево)", післяСписок, словами.map(х => х.назва)]]) {
  console.log("── %s ──\n%s", мітка, промпт);
  console.log("підпис під кадром: «Без фото малювались: %s»", підпис.join(", ") || "—");
  console.log("  її джинси в промпті: %s · кожна річ підпису є в промпті: %s\n",
    /джинси/.test(промпт) ? "ТАК" : "НІ", усі(промпт, підпис) ? "так" : "НІ");
}
