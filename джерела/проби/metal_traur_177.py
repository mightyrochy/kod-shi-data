# -*- coding: utf-8 -*-
"""Рядок 177: металева прикраса біля обличчя на похороні, коли прикрас вона не обирала — ДО (відсічення
вимкнено) і ПІСЛЯ. Каталог_повний, траурний пул (`траурне_відсічення`, сцена «похорон» через `траур_сцени`)
при `прикраси` «невідомо», «перли», «срібло», «золото». Друкує: скільки металевих прикрас біля обличчя
(`метал_біля_обличчя`: сережки, намисто, кольє, ланцюжок, кафф, шпилька…) лишилось у пулі й якого металу,
скільки металу не біля обличчя (браслет, каблучка, брошка) — його правка не чіпає, — і скільки прикрас
із перлами. Запуск: cd джерела && python3 проби/metal_traur_177.py"""
import collections, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as FK, траурний_регістр as ТР
КАТ = FK._прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"]
справжня = ТР.метал_біля_обличчя
біля = [r for r in КАТ if справжня(r)]
print("ФАКТ · каталог: металевих прикрас біля обличчя %d %s" % (len(біля), dict(collections.Counter(r["слот"] for r in біля))))
for мітка in ("ДО", "ПІСЛЯ"):
    ТР.метал_біля_обличчя = справжня if мітка == "ПІСЛЯ" else (lambda r: False)
    for пр in ("невідомо", "перли", "срібло", "золото"):
        тр = ТР.траур_сцени(dict(нагода="траур", місце="похорон", прикраси=пр))
        пул = [r for r in КАТ if not ТР.траурне_відсічення(r, тр)]
        б = [r for r in пул if справжня(r)]
        інш = [r for r in пул if r.get("метал") and not справжня(r) and r.get("слот") in ("браслет", "каблучка", "брошка", "прикраси")]
        перли = sum(1 for r in пул if "перл" in str(r.get("назва") or "").lower() and r.get("слот") in ("прикраси", "сережки", "намисто", "кольє"))
        print("ФАКТ · %-5s прикраси «%s»: пул %d · метал біля обличчя %d %s · метал не біля обличчя %d · прикрас із перлами %d"
              % (мітка, пр, len(пул), len(б), dict(collections.Counter(r["метал"] for r in б)), len(інш), перли))
ТР.метал_біля_обличчя = справжня
тр = ТР.траур_сцени(dict(нагода="траур", місце="похорон", прикраси="невідомо"))
print("ФАКТ · ж-11763 (Срібний ланцюжок, сід 5): %s" % ТР.траурне_відсічення(next(r for r in КАТ if r["id"].startswith("ж-11763@")), тр))
