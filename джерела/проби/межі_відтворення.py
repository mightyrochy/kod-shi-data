"""Відтворення записаних прогонів через межі Python, що читають відповідь моделі (наряд Е2-межі-поза-реєстром).

Кожна записана відповідь моделі вибору палітри (`*вибір_палітри_стилістка_*`) і виклику 0 (`*паспорт_виклик_0_*`) із
`аудит/проби/**/VIDPOVIDI/` іде в ту саму межу, що на живому шляху: вибір палітри — читачем кроку 2
(`вибір_палітри.прийняти`, форма «ВИБІР_ПАЛІТРИ»), виклик 0 — `паспорт_нагоди.паспорт_з_json`. Лічба: скільки
відповідей межа не прочитала (втрата через формат) і з якою причиною. На `main` до наряду той самий файл дає ДО
(читач вибору — `протокол.розбір_останній`, виклик 0 — свій зріз і `json.loads`).

Запуск (з `джерела/`): python3 проби/межі_відтворення.py
"""
import collections
import glob
import os
import sys

ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ)
import паспорт_нагоди as ПН  # noqa: E402

try:
    import схема_відповіді as _СВ  # noqa: E402
    _ФОРМА = _СВ.СХЕМИ_ВІДПОВІДІ["ВИБІР_ПАЛІТРИ"]
    прочитати_вибір = lambda т: _ФОРМА.прочитати(т)[:2]  # noqa: E731
    З_РЕЄСТРОМ = True
except KeyError:                                   # `main` до наряду: читач кроку 2 — той самий виклик, що там
    import протокол as _ПР  # noqa: E402
    прочитати_вибір = lambda т: _ПР.розбір_останній(т, ("scheme",))[:2]  # noqa: E731
    З_РЕЄСТРОМ = False


def відповідь(шлях):
    """Текст після заголовка «── ВІДПОВІДЬ … ──» запису (None — заголовка нема чи HTTP не 200)."""
    with open(шлях, encoding="utf-8") as ф:
        т = ф.read()
    і = т.find("── ВІДПОВІДЬ")
    if і < 0:
        return None
    заголовок, _, тіло = т[і:].partition("\n")
    return тіло.strip() if "HTTP 200" in заголовок else None


КОРІНЬ = os.path.join(os.path.dirname(ТУТ), "аудит", "проби")
лік = {}
for межа, зразок in (("вибір_палітри", "*вибір_палітри_стилістка_*.txt"), ("виклик_0", "*паспорт_виклик_0_*.txt")):
    файли = sorted(glob.glob(os.path.join(КОРІНЬ, "**", "VIDPOVIDI", зразок), recursive=True))
    причини = collections.Counter()
    for ш in файли:
        т = відповідь(ш)
        if т is None:
            причини["без відповіді HTTP 200"] += 1
            continue
        if межа == "вибір_палітри":
            об, чому = прочитати_вибір(т)
            if not isinstance(об, dict):
                причини[чому or "no_json_object"] += 1
        else:
            п = ПН.паспорт_з_json(т, {}, "")
            if п.get("помилка_формату"):
                причини[п["помилка_формату"]] += 1
    лік[межа] = (len(файли), причини)
    втрат = sum(в for к, в in причини.items() if к != "без відповіді HTTP 200")
    print("%-14s записів %3d · не прочитано %d%s" % (межа, len(файли), втрат,
                                                     " (%s)" % ", ".join("%s ×%d" % кв for кв in причини.items())
                                                     if причини else ""))

