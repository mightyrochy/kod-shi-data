if З_РЕЄСТРОМ:
    import json
    import bridge  # noqa: E402
    import міст_стилістка as МС  # noqa: E402
    d = dict(зріст=168, обхвати={"плечі": 98, "груди": 92, "талія": 74, "стегна": 99}, шкіра="#deb295",
             волосся=["#f1dbaa"], очі="#759087", паспорт=dict(нагода="побачення", місце="ресторан_високий", година=19))
    р1 = json.loads(bridge.виклик("вибір_палітри", json.dumps(d, ensure_ascii=False)))
    р2 = json.loads(bridge.виклик("вибір_палітри", json.dumps(dict(d, відповідь_моделі="Обираю теплу гаму.",
                                                                  промпт=р1["промпт"]), ensure_ascii=False)))
    assert р2.get("причина") == "no_json_object(prose)" and "format_error" in json.loads(р2["промпт_повтору"]), р2
    р3 = json.loads(bridge.виклик("вибір_палітри", json.dumps(dict(d, відповідь_моделі="Обираю теплу гаму."),
                                                              ensure_ascii=False)))
    # без `промпт` (так показ шле відповідь повтору) другого повтору нема: ранг коду, причина — у `без_моделі`
    assert "промпт_повтору" not in р3 and р3["вибір"]["обрала"]["scheme"] == "code_rank", р3
    assert str(р3["без_моделі"]).startswith("unreadable(no_json_object"), р3["без_моделі"]
    с = МС.прийняти('{"note": 1}', '{"task": "q"}')
    assert с.get("причина") and "format_error" in json.loads(с["промпт_повтору"]), с
    assert МС.прийняти("Так, пасує.", '{"task": "q"}').get("відповідь") == "Так, пасує."
    print("повтор словами: вибір палітри (один, далі ранг коду) і стилістка — так")
