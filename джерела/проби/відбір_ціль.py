"""Міряє, чи ремонт після структурної відмови адресує образ, названий стилісткою, разом зі складом."""
import json, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import повнота_образу as П


def головна():
    """Названо `о2` зі складом [a,b,c], прийнятих речей 0: у промпт ремонту мусить піти `о2` з [a,b,c]."""
    кандидати = {'верх': [dict(id=і, слот='верх') for і in 'abc']}
    блок = dict(код='слот_двічі')
    образи = [dict(ід='о1', речі=['a', 'b'], структура=dict(ок=False, блокери=[блок])),
              dict(ід='о2', речі=['a', 'b', 'c'], структура=dict(ок=False, блокери=[блок, блок]))]
    вердикт = dict(образи=образи)
    текст = json.dumps(dict(версія='1', обрано='о2', прибрати=[]), ensure_ascii=False)
    вибір = П.вибір_з_json(текст, вердикт, кандидати=кандидати)
    повнота = П.повнота_набору(вердикт, кандидати=кандидати, вибір=вибір)
    ремонт = П.вердикт_повноти(вердикт, обрано=повнота['образ'])
    print(json.dumps(dict(названо=вибір['названо'], прийнятих_речей=len(вибір['ід']), ціль_коду=повнота['образ'],
                          ремонт={о['ід']: о['речі'] for о in ремонт['образи']}), ensure_ascii=False))


головна()
