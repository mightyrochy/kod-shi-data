"""Входи емітентів `формальність.py` (повний каталог і граничні речі) для звірки ваги ДО/ПІСЛЯ."""
import gzip, json, os, pathlib
КОДИ = ('casual', 'smart_casual', 'business_casual', 'business_formal', 'cocktail', 'black_tie', 'white_tie')
НАГОДИ = (('біле_вечір', dict(нагода='весілля_гість', зарезервований_колір='near_white', пора='вечір')),
          ('ділова', dict(нагода='робота', дрес_код='business_formal', пора='день')),
          ('похорон', dict(нагода='траур', місце='похорон')), ('фото', dict(нагода='свято', фото=True)),
          ('траур_стан', dict(нагода='траур', траур={'близькість': 'close', 'місяців': 6})))


def набори():
    """Граничні речі × нагоди; далі кожна річ каталогу × коди, нагоди й пари з якорями-взуттям у трьох сценах."""
    import feed as Ф, outfit as О, формальність as F, сценарій as СЦ

    def нагода(kw, речі):
        """Аргументи `нагода_палітра` за описом сценарію (наряд Код-сценарій-один-опис): поля — в опис, решта — як є."""
        return ([СЦ.з_нагоди({к: v for к, v in kw.items() if к in СЦ.ОПИСАНІ_МНОЖИНА})],
                dict({к: v for к, v in kw.items() if к not in СЦ.ОПИСАНІ_МНОЖИНА}, речі=речі))
    for hx in ('#e00000', '#ff00ff', '#ffcc00', '#0040ff', '#f2ead8', '#d8c3a5', '#808080', '#111111'):
        for пл, слот, тип in ((0.06, 'шарф', 'шарф'), (0.3, 'верх', 'блуза'), (0.6, 'сукня', 'сукня')):
            р = dict(id='синт%s-%s' % (hx, слот), назва=тип, слот=слот, тип=тип, colors=[dict(hex=hx, coverage=1.0)],
                     площа=пл, блиск=3, місце_стилістки={'біля_обличчя': 'так'})
            for назва, kw in НАГОДИ + (('її_похорон', dict(нагода='траур', місце='похорон', траур_пулу={'її_вибір': [р['id']]})),):
                сц, kw2 = нагода(kw, [р])
                yield р['id'] + '@' + назва, 'нагода_палітра', [О.елементи([р], стан='надворі')] + сц, kw2
    кеш = pathlib.Path(os.environ['TMP']) / 'е3_каталог.json.gz'
    if not кеш.exists():
        with gzip.open(кеш, 'wt', encoding='utf-8') as ф:
            json.dump(Ф.база_прогону(Ф.каталог_на_диску('каталог_повний.xml'), ліміт_фото=0)['каталог'], ф, ensure_ascii=False)
    with gzip.open(кеш, 'rt', encoding='utf-8') as ф:
        каталог = json.load(ф)
    якорі = [next(р for р in каталог if р.get('тип') == т) for т in ('кросівки', 'човники')]
    сцени = (('вечір_bt', F.сценарій(dict(дрес_код='black_tie', пора='вечір', відкриті_зони='none'))),
             ('день_casual', F.сценарій(dict(дрес_код='casual', пора='день'))),
             ('бізнес', F.сценарій(dict(дрес_код='business_casual', пора='день', відкриті_зони='one'))))
    print('каталог', len(каталог), flush=True)
    for р in каталог:
        Е = О.елементи([р], стан='надворі')
        for код in КОДИ:
            yield str(р['id']) + '@' + код, 'вимоги_коду', [Е, код], {}
        for назва, kw in НАГОДИ:
            сц, kw2 = нагода(kw, [р])
            yield str(р['id']) + '@' + назва, 'нагода_палітра', [Е] + сц, kw2
        for я in (я for я in якорі if я is not р):
            Е2 = О.елементи([р, я], стан='надворі')
            for назва, сцен in сцени:
                yield '%s+%s@%s' % (р['id'], я['id'], назва), 'формальність_образу', [Е2], dict(сцен=сцен, образ=None)
