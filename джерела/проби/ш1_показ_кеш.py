"""Ш-1, важіль 1: `показ` і `опис` більше не розбирають фід на кожному виклику.

ДО — кеш показу скидається перед кожним викликом (так ходив main: `читати_yml` щоразу);
ПІСЛЯ — кеш живе. Той самий набір, що за один збір на стенді (сід 3): шість `показ`
(4 картки по 5 речей і 2 довідники по 40) і два `опис`. Друкує час і чи всі відповіді
байт у байт ті самі. Запуск із теки `джерела` (потрібен розпакований каталог_повний.xml)."""
import json, os, sys, time
sys.path.insert(0, ".")
import bridge as B, міст_опис as МО, feed as F, фід_розбір as ФР

вх = json.load(open("стенд_вх.json", encoding="utf-8"))
вх["каталог"] = F.каталог_на_диску("каталог_повний.xml")
ід = [o["id"] for o in F.читати_yml(вх["каталог"])[0][::97]][:80]
пять = [ід[i:i + 5] for i in range(0, 20, 5)]
кроки = ([("показ", dict(вх, речі=р)) for р in пять] + [("показ", dict(вх, речі=ід[:40])),
         ("показ", dict(вх, речі=ід[40:80]))]
         + [("опис", dict(вх, речі=р, підпис="проба Ш-1")) for р in пять[:2]])


def прогін(скидати):
    """Усі кроки одного збору; `скидати` — кеш показу порожній перед кожним (як main)."""
    вих, т0 = [], time.time()
    for ім, д in кроки:
        if скидати:
            МО._КЕШ_ПОКАЗУ.clear(); ФР._ОФЕРИ_КЕШ.clear()
        вих.append(B.виклик(ім, json.dumps(д, ensure_ascii=False)))
    return вих, time.time() - т0


до, с_до = прогін(True)
МО._КЕШ_ПОКАЗУ.clear(); ФР._ОФЕРИ_КЕШ.clear()
після, с_після = прогін(False)
print("кроків %d (показ ×6, опис ×2) · ДО %.1f с · ПІСЛЯ %.1f с (перший розбір — у першому показі)"
      % (len(кроки), с_до, с_після))
print("відповіді байт у байт ті самі: %s (%d з %d)"
      % (до == після, sum(a == b for a, b in zip(до, після)), len(до)))
