"""КОЛО-РОЛІ-3 (наряд 2.1-А, рядки 8050–8052): «той самий тон» трьома способами на кольорових речах каталогу (`нейтраль_меж`
«ні»). Дуги: ролі 5 схем `палітра_схеми.СХЕМИ` × 12 якорів кола; вікна палітри (`палітра_практична`, сім'ї без очей; у
стенда й ж1–ж9 однакові); очі стенда й ж1–ж9. Пара — річ × дуга. Друкує: (1) `у_дугах_кола` ≠ `колір_відношення.сила`
same_hue від центру дуги (L*, C* речі), на краю дуги 0.5 (пул-точка, носії) і кінці згасання 0.05 (суд, `описує_річ`);
(2) K-PAL-17 `річ_з_фото.частка_тону` ≥ 0.5 ≠ тон `у_вікнах_меж` (`у_дугах_кола` до кінця згасання; очі K-PAL-17 — та
сама `сила_відлуння_очей`, що `у_відлунні_очей`); (3) сила 0.05–0.5 — пари й речі, де пул/носії і суд кажуть різне.
Запуск із джерела/: python3 проби/коло_ролі_тон_вікна.py"""
import json, glob, sys, collections as K; sys.path.insert(0, ".")
import bridge as B, colorspace as cs, колір_річ as КР, колір_відношення as КВ, палітра_схеми as ПС, palettes as ПЛ, річ_з_фото as РФ
вх0 = json.load(open("стенд_вх.json", encoding="utf-8")); B.виклик("запити", json.dumps(вх0, ensure_ascii=False))
речі = [r for r in B.каталог_останнього_пакета() if КР.межі_кольору(r) and КР.нейтраль_меж(r) == "ні"]
ролі = {д for i in range(12) for з in ПС.СХЕМИ.values() for д in з["тон"](cs.з_кола_художника(30.0 * i)).values() if isinstance(д, tuple)}
жінки = [вх0] + [dict(вх0, шкіра=Ж["skin"][0], волосся=Ж["hair"], очі=Ж["eyes"]) for Ж in
                 (json.load(open(f, encoding="utf-8")) for f in sorted(glob.glob("../аудит/проби/жінки/ж*.json")))]
вікна = {tuple(д) for вх in жінки for с, дд in ПЛ.палітра_практична(B._features(вх)[0])["вікна"]["сім_ї"].items() if с != "очі" for д in дд}
зріз, П2 = (lambda с, п: "так" if с[0] >= п else "ні" if с[1] < п else "невідомо"), ((False, КВ.КРАЙ_ДУГИ), (True, КВ.КІНЕЦЬ_ЗГАСАННЯ))
Л, зона = K.Counter(), K.defaultdict(set)
for x in речі:
    вим, (L, C, h) = КР.не_вимір(x) is None, cs.lch(tuple(x["lab"]))
    for мн, дд in (("ролі", ролі), ("вікна", вікна)):
        for д in дд:
            ц = КВ._параметри_дуги(д)[0]; р0 = КР.запис_кольору(dict(lab=ПЛ.lab_з_lch(L, C, ц)))
            с = КВ.сила(КР.запис_кольору(x), р0, "same_hue", певність=False); Л[(мн, "пар")] += 1
            for дк, п in П2:
                а, б = КР.у_дугах_кола(x, [д], до_кінця_згасання=дк), зріз(с, п)
                Л[(мн, "%.2f дуга ≠ same_hue" % п)] += а != б; Л[(мн, "%.2f так↔ні" % п)] += {а, б} == {"так", "ні"}
            if КР.у_дугах_кола(x, [д]) != КР.у_дугах_кола(x, [д], до_кінця_згасання=True):
                Л[(мн, "сила 0.05–0.5, пар")] += 1; зона[мн].add(x["id"])
            if вим and мн == "вікна":
                Л[("K-PAL-17", "вікна: частка тону ≠ у_вікнах_меж")] += (РФ.частка_тону(C, h, [д]) >= 0.5) != (КР.у_дугах_кола(x, [д], до_кінця_згасання=True) == "так")
print("кольорових речей %d (вимірів %d), дуг ролей %d, вікон %d" % (len(речі), sum(КР.не_вимір(x) is None for x in речі), len(ролі), len(вікна)))
for к, v in sorted(Л.items()): print("  %-9s %-34s %7d" % (*к, v))
for мн, з in sorted(зона.items()): print("  %-9s речей із силою 0.05–0.5 хоч на одній дузі %d" % (мн, len(з)))
