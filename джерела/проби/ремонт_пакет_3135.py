"""Рядок 3135 · довжина пакета ремонту (ВЕРДИКТ_V1 → ОБРАЗИ_V1) на стенді `стенд_вх.json` (пул руки 1 ~500 речей),
коли складання повернуло 10 образів (стільки просить ПАКЕТ_V1) і коли 33 (живі 12 Б/09, рука 1: qwen3.5-9b до стелі
виводу). Символи, токени (3,17 симв./т. — 205 907 симв. того запиту дали n_keep 64 988) проти n_ctx 57 344 мінус стеля
виводу 4000, скільки образів дійшло у вердикт, найбільші блоки. Те саме для частин пулу (#частин=2: 18 + 3 образи).
Нічого не викликає. Запуск: cd джерела && python3 проби/ремонт_пакет_3135.py"""
import json, os, sys
Д = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, Д); os.chdir(Д)
import bridge as B
L = lambda x: len(json.dumps(x, ensure_ascii=False, separators=(",", ":")))
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), варіантів=10, ремонт_варіантів=5, без_фото=1)
пул = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["пакети"]["1"]["пул"]
сл = [с for с in ("верх", "низ", "взуття", "сумка", "верхній_шар") if пул.get(с)]
образи = lambda n, з=0: [dict(ід="о%d" % (і + 1), підпис="образ %d" % (і + 1),
                              речі=[пул[с][((і + з) * 3 + k) % len(пул[с])]["н"] for k, с in enumerate(сл)])
                         for і in range(n)]
текст = lambda об: json.dumps(dict(версія="1", образи=об), ensure_ascii=False)
print("пул руки 1: %d речей" % sum(len(v) for v in пул.values()))
for назва, дод in (("10 образів", dict(текст_моделі=текст(образи(10)))),
                   ("33 образи", dict(текст_моделі=текст(образи(33)))),
                   ("частини 18+3", dict(тексти_моделі=[текст(образи(18)), текст(образи(3, 18))]))):
    в = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, **дод), ensure_ascii=False)))
    п = в["промпт_ремонту"]; д = json.loads(п); т = round(len(п) / 3.17)
    print("%-13s → у вердикті ремонту %2d образів · %6d симв. ≈ %5d т. (%s у 53 344) · блоки: %s" % (
        назва, len(д["verdict"]), len(п), т, "влазить" if т <= 57344 - 4000 else "НЕ ВЛАЗИТЬ",
        ", ".join("%s %d" % (к, L(v)) for к, v in sorted(д.items(), key=lambda x: -L(x[1]))[:4])))
