/* Виконує справжній етап фото-заміни: новий опис і атомарна відмова при збої. */
const fs = require('fs'), path = require('path'), assert = require('assert/strict');
const код = fs.readFileSync(path.join(__dirname, '../показ/збирання_руки.js'), 'utf8');
const етап = код.slice(код.indexOf('    const зам4 ='), код.indexOf('    вхОпису = {...вхОпису, заміна_вирішена: 1}'));
const виконати = new (Object.getPrototypeOf(async function(){}).constructor)('ctx',
  'with(ctx){' + етап + '; return {в4, обраніІД, замінаФото};}');
async function проба(збій){
  const запити = [];
  const ctx = {в4:{заміна:{стан:'spares', річ:'old', чому:'colour', запасні:[{id:'new'}]},
      опис:{текст:'Помаранчева сумка.', як_носити:['Носи помаранчеву сумку.']}},
    замінаФото:null, ЗБ:{діагноз:[]}, фотоПоказано:true, обраніІД:['top','old'], т4:'старий текст',
    в:null, текст:'старий текст', підпис:'Помаранчева сумка',
    вхідОпису:{речі:['top','old']}, вхОпису:{ід:['top','old']}, пвн:{номери:{}},
    оголКартки:[], дібраніКодом:{}, свідоміКартки:[], свідоміКарткиІд:[],
    малюватиТокениП(){}, підписатиКадри:()=>[], кадриЗАдрес:async()=>[], шаблонОписуП:в=>в,
    містП:async(що,вхід)=>{запити.push(вхід); return {промпт:вхід.заміна?'вибір':'новий опис',фото:[]};},
    модельРукиП:async блоки=>{if(збій===true && блоки[0].text==='новий опис') throw Error('збій опису'); return блоки[0].text;},
    к:{рука:'2',лічильники:{викликів:0},станОбриву:()=>({}),зОбривом:(_,в)=>в,запамʼятатиЗапит(){},
      відМоделіРуки:async в=>в.заміна_запасні
        ? {заміна:{стан:'accepted',річ:'old',на:'new',ід:['top','new']}}
        : {перевірено:збій!=='суд',речі:['top',збій==='склад'?'old':'new'].map(id=>({id})),
          опис:{текст:'Чорний шопер.',як_носити:['Носи чорний шопер.']}}}};
  const вихід = await виконати(ctx);
  if(збій){assert.deepEqual(вихід.обраніІД,['top','old']);assert.equal(вихід.в4.опис.текст,'Помаранчева сумка.');}
  else {assert.deepEqual(запити[1].речі,['top','new']);assert.equal(запити[1].заміна,null);
    assert.deepEqual(вихід.обраніІД,['top','new']);assert.equal(вихід.в4.опис.текст,'Чорний шопер.');
    assert.deepEqual(вихід.в4.опис.як_носити,['Носи чорний шопер.']);assert(вихід.замінаФото.застосовано);
    assert.equal(ctx.підпис,'');assert.equal(ctx.в.опис.текст,'Чорний шопер.');}
}
(async()=>{for(const стан of [false,true,'склад','суд']) await проба(стан);
  console.log('Фото-заміна: новий опис і «Як це носити»; збій опису зберігає попередній склад і текст.');
})().catch(е=>{console.error(е);process.exitCode=1;});
