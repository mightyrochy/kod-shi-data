"""Спільний суд прямого й фото-вибору: учасники, пул і закріплена річ."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import пропозиція_заміни as П
import заміна_з_фото as Ф


def головна():
    """Відрізняє перенесення від відомого зауваження на наступниці речі."""
    словник = {і: dict(id=і, слот=с) for і, с in [('а', 'верх'), ('б', 'низ'), ('в', 'верх')]}
    пул = {'верх': [словник['в']]}
    учасник = ['б']
    def суддя(набори):
        """Дає те саме правило на старій, новій або іншій позиції образу."""
        return [dict(знахідки=[dict(правило='K-CLR-02', суть='вимір', сила='strong', сила_нп=1,
                    речі=['а'] if 'а' in набір else учасник)], блокує=None) for набір in набори]
    запит = dict(річ='а', чому='colour', запасні=['в'])
    assert Ф.запасні(запит, ['а', 'б'], {}, [], пул, словник, {}, суддя)['стан'] == 'no_spares'
    assert Ф.вирішити({'на': 'в'}, запит, ['а', 'б'], суддя, словник, пул)['стан'] == 'refused'
    учасник[:] = ['в']
    assert Ф.вирішити({'на': 'в'}, запит, ['а', 'б'], суддя, словник, пул)['стан'] == 'accepted'
    assert not П.перевірити_ід(['а', 'б'], ['в', 'б'], словник, {}, [], суддя)['образ']
    assert not П.перевірити_ід(['а', 'б'], ['в', 'б'], словник, {'в': словник['в']}, ['а'], суддя)['образ']
    словник['а']['закріплена'] = True
    assert Ф.вирішити({'на': 'в'}, запит, ['а', 'б'], суддя, словник, пул)['стан'] == 'refused'
    print('Фото й прямий вибір: перенесення відхилено; наступниця прийнята; пул і явний вибір збережено')


if __name__ == '__main__':
    головна()
