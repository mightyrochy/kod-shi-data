"""K-SHO-14 (ширина — незалежна вісь) + K-SHO-15 (розмір — ворота, не скор).

ДО ПРАВКИ: K-SHO-14 не мав емітента взагалі — ID стояв лише в докстрінгу
`ворота_розміру` («K-SIZ-01 + K-SHO-13/14/15»), тобто правило вважалось
виконаним тим, що його назвали поруч із сусідом. K-SHO-15 емітент мав, і той
емітент недосяжний: гілка «припуск забагато» вимагає `устілка_см` (0 із 2 096
карток — розмірна таблиця глушить одиничне читання) і `довжина_стопи_мм`
(в анкеті нема).
ПІСЛЯ: обидва стоять на полях картки, яких фід раніше не діставав, — `повнота`
(151 річ, 7.2 %) і `розмірність` (28 речей, 1.3 % після зняття шаблонного
застереження магазину), — і жодне не потребує виміру тіла."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
взуття = [c for c in кат if c.get("слот") == "взуття"]
print("взуття в пакеті %d · із повнотою %d · із розмірністю %d"
      % (len(взуття), sum(1 for c in взуття if c.get("повнота")),
         sum(1 for c in взуття if c.get("розмірність"))))
сукня = next(c for c in кат if c.get("слот") == "сукня")
for ключ, ум in (("K-SHO-14", lambda c: c.get("повнота") in ("вузька", "широка")),
                 ("K-SHO-15", lambda c: c.get("розмірність"))):
    пара = next((c for c in взуття if ум(c)), None)
    print("%s · пара «%s» (повнота %s, розмірність %s)"
          % (ключ, пара["назва"][:40], пара.get("повнота"), пара.get("розмірність")))
    вм = json.loads(B.виклик("від_моделі", json.dumps(
        dict(вх, ід=[сукня["id"], пара["id"]]), ensure_ascii=False)))
    зн = ((вм.get("вердикт") or {}).get("образи") or [{}])[0].get("знахідки") or []
    р = next((z for z in зн if z.get("правило") == ключ), None)
    print("   у вердикті:", "НЕМА" if not р else
          "%s/%s %.2f · %s" % (р["сила"], р["регістр"], р["сила_нп"], р["суть"][:60]))
    assert р, "%s мусить дати рядок вердикту на картці, що оголошує вісь" % ключ
