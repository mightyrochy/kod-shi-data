"""Рядок 1650 (ФОКУС-3, п.12): три знахідки R-CHEV-08 (`регістр_уваги.знахідка_уваги`) — «колір
тримає увагу» і «річ помітна собою» за метою «приховати», «увагу не тримає ніщо» за «експресією» —
на дроті моделі (`дріт_моделі._знахідка`): скільки вузлів везуть `statements`, скільки ще `what`
прозою і ремонт текстом, і чи є кирилиця у вузлі англійського промпта. Образи складені тут же.
Запуск із `джерела`: python3 проби/увага_заяви.py"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import регістр_уваги as РУ, дріт_моделі as ДМ
речі = [dict(id="ч1", слот="сукня", назва="Сукня червона", L=50.0, C=75.0),
        dict(id="т1", слот="верх", назва="Топ з відкритими плечима", виріз="відкритий", L=30.0, C=5.0),
        dict(id="с1", слот="низ", назва="Спідниця сіра", L=55.0, C=3.0),
        dict(id="б1", слот="взуття", назва="Туфлі бежеві", L=70.0, C=12.0)]
ел = lambda *ід: [dict(річ=r["id"], слот=r["слот"], L=r["L"], C=r["C"], площа=.4) for r in речі if r["id"] in ід]
случаї = [("приховати", ел("ч1", "т1", "б1")), ("експресія", ел("с1", "б1"))]
вузли = [(м, ДМ._знахідка(dict(z, ід="f%d" % н)))
         for м, E in случаї for н, z in enumerate(РУ.знахідка_уваги(E, речі, м))]
кир = re.compile("[а-яіїєґ]", re.I)
код = lambda з: next(iter(з)) if isinstance(з, dict) else з          # дріт: {code: values} чи code
укр = lambda в: bool(кир.search(json.dumps({к: v for к, v in в.items() if к != "items"}, ensure_ascii=False)))
for м, в in вузли:
    print("%-10s statements=%s · what прозою=%s · fix=%s · кирилиця=%s" % (
        м, [код(з) for з in в.get("statements") or []] or "—", "what" in в,
        [код(з)[:40] for з in в.get("fix") or []], укр(в)))
print("УСЬОГО вузлів %d · із statements %d · what прозою %d · з кирилицею %d" % (
    len(вузли), sum(bool(в.get("statements")) for _, в in вузли), sum("what" in в for _, в in вузли),
    sum(укр(в) for _, в in вузли)))
