"""Е2-втрата-слова п.6 (рядок 1413): «схему обрала вона» на записаному прогоні ж3_театр_тріада (4411f706).
Вхід мосту складено з її палітри й вибору стилістки прогону тим самим `злитиСтилісткуП` (node) і правилом
`вхідМостаП`; друкує три ознаки — міст (`для_суду`), ключ пулу (`входи_пакета`), шапку експорту (JS-вираз
`схема_обрана` із `показ/збирання_образів.js`). Запуск з кореня: python3 джерела/проби/е2_втрата_слова_вибір.py [дерево]"""
import json, os, re, subprocess, sys, warnings
warnings.filterwarnings("ignore")
Д = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else ".")
sys.path.insert(0, os.path.join(Д, "джерела"))
import вибір_палітри as ВП, міст_пакет as МП  # noqa: E402
т = open("аудит/проби/автоживий-4411f70673afbfb20e780bd4f3764e830c51a582/ж3_театр_тріада/вердикти.txt",
         encoding="utf-8").read()
з = json.loads(т[т.find("{"):])
пал = з["спільне"]["вхід_прогону"]["палітра"]
вп = з["прогони"][0]["спільне"]["етапи"]["прогін"]["вибір_палітри"]
вс = {"вибір": {"обрала": вп["обрала"], "причини": вп["причини"]}, "знахідки": [], "відхилено": []}
def js(файл, шаблон):
    return re.search(шаблон, open(os.path.join(Д, "джерела/показ", файл), encoding="utf-8").read(), re.S).group(0)
злиття = js("палітра.js", r"function злитиСтилісткуП\(.*?\n\}")
ознака = js("збирання_образів.js", r"схема_обрана:\(.*?\)\}").split(":", 1)[1][:-1]
код = "%s\nconst пал=%s, ст=злитиСтилісткуП(пал, %s);\n" \
      "const вх=Object.assign({}, пал.гілка==null?{}:{гілка:пал.гілка}, (пал.схема||(ст&&ст.схема))?{схема:пал.схема||ст.схема}:{}," \
      " (ст&&ст.схема)?{схема_стилістки:true}:{}, ст?{вибір_стилістки:ст.запис}:{});\n" \
      "console.log(JSON.stringify({вх, експорт: %s}));" % (злиття, json.dumps(пал, ensure_ascii=False),
                                                           json.dumps(вс, ensure_ascii=False), ознака)
р = json.loads(subprocess.run(["node", "-e", код], capture_output=True, text=True, check=True).stdout)
вх = р["вх"]
print("дерево:", Д)
print("її палітра прогону:", {к: пал.get(к) for к in ("гілка", "схема")}, "· стилістка:", вп["обрала"])
print("вхід мосту:", {к: v for к, v in вх.items() if к != "вибір_стилістки"})
print("міст для_суду scheme:", ВП.для_суду(вх)["обрала"].get("scheme"))
print("ключ пулу схему_обрала_вона:", bool(МП.входи_пакета(вх, None, None, None).get("схему_обрала_вона")))
print("шапка експорту пал_схема_обрана:", "так" if р["експорт"] else "ні")
