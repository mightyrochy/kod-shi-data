# -*- coding: utf-8 -*-
"""Реєстр А (рядок 5630), клас А6: картка без показного фото. Друкує, скільки речей каталогу
(1) не мають жодного кадру в ряду картки (`кадри_речі` порожній) — за причиною `чому_без_кадру`;
(2) несуть `без_показу` з виміру приладу `показне_фото` (не відкрився жоден кадр) і тому поза
пулом рук 1–2; (3) хости, що заборонили чужий показ (CORP). По крамницях — перші вісім.
Запуск: cd джерела && python3 проби/каталог_проблеми_а_без_кадру.py"""
import collections, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed as Ф, фід_фото as ФФ
оф = Ф.читати_yml(Ф.каталог_на_диску("каталог_повний.xml"))[0]
зб, сп, хо = Ф.читати_збагачення(), ФФ._спільні_фото(оф), ФФ._хости_крамниць(оф)
причини, крамниці, без = collections.Counter(), collections.Counter(), collections.Counter()
for o in оф:
    з, м = зб.get(o["id"]), o.get("магазин")
    if not ФФ.кадри_речі(o, сп.get(м) or {}, хо, з.get("фото") if isinstance(з, dict) else None):
        причини[ФФ.чому_без_кадру(o, сп.get(м) or {}) or "кадр жнив відсіяно"] += 1; крамниці[м] += 1
    if o.get(ФФ.ПОЛЕ_БЕЗ_ПОКАЗУ):
        без[o[ФФ.ПОЛЕ_БЕЗ_ПОКАЗУ]] += 1
д = ФФ.читати_показ()
print("картка без кадру:", sum(причини.values()), "з", len(оф), "·", dict(причини.most_common()))
print("  по крамницях:", крамниці.most_common(8))
print("без_показу (поза пулом рук 1–2):", sum(без.values()), dict(без), "· відновлено адрес зі сторінки:", len(д.get("адреси") or {}))
print("хости без чужого показу (CORP):", list(д.get("хости") or ()), "· вимір показності знято:", д.get("знято"))
