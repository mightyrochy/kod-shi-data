"""НП-в, наряд 3.7: що код вирішує з плитки нагоди. 18 плиток (місце — те, що шле плитка: `МІСЦЕ_ПЛИТКИ_НАГОДИ`),
година 11, 19 і «—» (без години: частину дня дає хід мовної моделі, як заглушка стенда — коли підпис плитки
називає вечір), без числа ошатності; плюс діловий дрес-код. Друкує базу смуги суду, вечір, зони, вето, сумку,
траур, дистанцію, профіль палітри. Злиття без причини — дві плитки з тим самим рішенням, чиї смуги дали РІЗНІ
рядки таблиці (збіг чисел, а не той самий вимір), за трьома годинами. Останній рядок — ті самі плитки з одним щаблем мовної моделі
(neat 5–6): скільки різних смуг дає ключ. Ганяти на двох SHA й порівняти. Запуск із `джерела`."""
import sys, os, itertools
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import формальність as Ф, суд_від_моделі as СВ, траурний_регістр as ТР, дистанція as Д
import мовний_шар as МШ, сценарій as СЦ, паспорт_нагоди as ПН
ПІДПИС = {н["ключ"]: н["підпис"] + " " + н["нота"] for н in ПН.довідник()["нагоди"]}
def година_з_ходу(к, м):
    """Без години: хід мовної моделі дає part_of_day, коли підпис плитки називає вечір; код бере його з паспорта."""
    в = {"part_of_day": "evening"} if "вечір" in ПІДПИС.get(к, "").lower() else {}
    с = dict(нагода=к, місце=м, година=11, темп_c=18, типові_поля=["година", "темп_c"])
    return ПН.з_показу(с, МШ.паспорт_з_шару(в, с, None, {})["паспорт"])[0].get("година")
рішення, бази, смуги_щабля = {}, {}, set()
for к, м in ПН.МІСЦЕ_ПЛИТКИ_НАГОДИ.items():
    for г, код in ((11, None), (19, None), ("—", None)) + (((11, "business_casual"),) if к in ("робота", "співбесіда") else ()):
        гг = година_з_ходу(к, м) if г == "—" else г
        с = Ф.сценарій(місце=м, нагода=к, година=гг, код=код)
        сц = dict(нагода=к, місце=м, година=гг)
        ряд = "діап=%s вечір=%d зони=%s вето=%s сумка=%d траур=%d дист=%s профіль=%s" % (
            "%g–%g" % с["діапазон"], с["вечір"], с.get("відкриті_зони") or "—",
            "|".join(в.split(" (")[0] for в in с["вето"]) or "—", not СВ.спорт_чи_дім(сц),
            ТР.траур_випадку(нагода=к, місце=м) is not None, Д.з_сценарію(сц)["дистанція"],
            Ф.профіль_палітри(година=гг, траур=м in ТР.МІСЦЯ_ПОДІЇ_ТРАУРУ, дрес_код=код))
        print("%-14s %2s→%-4s %-15s %s · %s" % (к, г, гг, код or "", ряд, с["чому"][0]))
        if not код:   # злиття — за трьома годинами; рядок дрес-коду є лише в двох плиток
            рішення.setdefault(к, []).append(ряд); бази.setdefault(к, set()).add(с["чому"][0].split("→")[0])
        смуги_щабля.add(Ф.сценарій(місце=м, нагода=к, година=гг, код=код, смуга=(5, 6))["діапазон"])
злиття = [(а, б) for а, б in itertools.combinations(рішення, 2) if рішення[а] == рішення[б] and бази[а] != бази[б]]
print("злиттів без причини: %d %s" % (len(злиття), " ".join("%s=%s" % п for п in злиття)))
print("з одним щаблем мовної моделі (neat 5–6) різних смуг на %d плиток: %d %s" % (len(рішення), len(смуги_щабля), sorted(смуги_щабля)))
