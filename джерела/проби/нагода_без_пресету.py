"""НП-в: що код вирішує з плитки нагоди без пресету виду. 18 плиток (місце — те, що шле плитка), година
11, 19 і «—» (без години: частину дня дає хід мовної моделі, як заглушка стенда — коли підпис плитки
називає вечір), без числа ошатності; плюс діловий дрес-код. Друкує базу смуги суду, вечір, зони, вето,
сумку, траур, дистанцію, профіль палітри. Ганяти на двох SHA й порівняти. Запуск із `джерела`."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import формальність as Ф, суд_від_моделі as СВ, траурний_регістр as ТР, дистанція as Д
import мовний_шар as МШ, сценарій as СЦ, паспорт_нагоди as ПН
МІСЦЕ = {"щоденне": "кафе", "дім": "дім", "прогулянка": "прогулянка", "робота": "офіс_корпоративний",
         "співбесіда": "співбесіда", "школа": "школа_батьківські", "формал_день": "конференція",
         "формал_вечір": "ресторан_високий", "весілля_денне": "весілля_денне",
         "весілля_гість": "весілля_вечірнє", "свято": "святкова_вечеря", "траур": "похорон",
         "побачення": "ресторан_районний", "театр": "театр", "музей": "музей",
         "церква": "церква_служба", "спорт": "спорт", "подорож": "подорож_переліт"}
ПІДПИС = {н["ключ"]: н["підпис"] + " " + н["нота"] for н in ПН.довідник()["нагоди"]}
def година_з_ходу(к, м):
    """Без години: хід мовної моделі дає part_of_day, коли підпис плитки називає вечір; код бере його з паспорта."""
    в = {"part_of_day": "evening"} if "вечір" in ПІДПИС.get(к, "").lower() else {}
    с = dict(нагода=к, місце=м, година=11, темп_c=18, типові_поля=["година", "темп_c"])
    return СЦ.з_показу(с, МШ.паспорт_з_шару(в, с, None, {})["паспорт"])[0].get("година")
for к, м in МІСЦЕ.items():
    for г, код in ((11, None), (19, None), ("—", None)) + (((11, "business_casual"),) if к in ("робота", "співбесіда") else ()):
        гг = година_з_ходу(к, м) if г == "—" else г
        с = Ф.сценарій(місце=м, нагода=к, година=гг, код=код)
        сц = dict(нагода=к, місце=м, година=гг)
        print("%-14s %2s→%-2s %-15s діап=%s вечір=%d зони=%s вето=%s сумка=%d траур=%d дист=%s профіль=%s" % (
            к, г, гг, код or "", "%g–%g" % с["діапазон"], с["вечір"], с.get("відкриті_зони") or "—",
            "|".join(в.split(" (")[0] for в in с["вето"]) or "—", not СВ._спорт_чи_дім(сц),
            ТР.траур_випадку(нагода=к, місце=м) is not None, Д.з_сценарію(сц)["дистанція"],
            Ф.профіль_палітри(година=гг, місце=м, траур=м in ТР.МІСЦЯ_ПОДІЇ_ТРАУРУ, дрес_код=код)))
