# -*- coding: utf-8 -*-
"""Приймальна проба Н-P12: дрібні шви показу й моста.

Друкує ФАКТИ, а не «ок»: скільки «ребро: )» лишилось у промпті ремонту (0),
скільки читань `образ_ші` в показі (0), які поля виходу `запити` не мають
жодного читача (порожньо), чи їде `імʼя` у вхід моста, і чи дісталась
`черга_на_вхід` до `питання`.
Запуск: PYTHONPATH=. python3 проби/шви_показу.py
"""
import json, re, pathlib, subprocess
import bridge as B

вх = json.load(open("стенд_вх.json"))
d0 = dict(вх, сценарій=dict(нагода="вечірка", місце="ресторан", година=19, темп_c=18, дрес_код="cocktail"),
          випадок="коктейль, ресторан, 19:00")
з = json.loads(B.виклик("запити", json.dumps(d0, ensure_ascii=False)))
пул = json.loads(з["руки"]["1"])["пул"]
ядро = [пул[с][0]["н"] for с in ("верх", "низ", "взуття") if пул.get(с)]
текст = json.dumps(dict(образи=[dict(підпис="о1", речі=ядро)]), ensure_ascii=False)
в = json.loads(B.виклик("від_моделі", json.dumps(dict(d0, текст_моделі=текст), ensure_ascii=False)))
пр = в.get("промпт_ремонту") or ""
print("промпт ремонту: %d символів · «ребро: )» %d · «: )» %d"
      % (len(пр), пр.count("ребро: )"), пр.count(": )")))
print("_без_ід на рядку вузла: %r" % B._без_ід("вузол напруги — «низ» (0.50, 1 ребро: K-WEA-01); міняти річ"))
показ = pathlib.Path("показ.html").read_text(encoding="utf-8")
print("показ.html: «образ_ші» %d" % показ.count("образ_ші"))
тексти = показ + "\n".join(p.read_text(encoding="utf-8") for p in pathlib.Path(".").glob("*.py") if p.name != "bridge.py")
print("поля виходу `запити` без читача: %s"
      % (sorted(k for k in з if k not in тексти) or "нема (усі %d мають ≥1 читача)" % len(з)))
print("від_моделі: черга_на_вхід у виході %s · питань %d · з них про вхід %d"
      % ("є" if "черга_на_вхід" in в else "нема (влита в `питання`)", len(в.get("питання") or []),
         sum(1 for z in (в.get("питання") or []) if "входу нема" in str(z.get("суть") or ""))))
print("вхідМостаП кладе `імʼя`: %s · пакет показу читає `вх.імʼя`: %s"
      % ("імʼя: п.імʼя" in показ, "вх.імʼя" in показ))
