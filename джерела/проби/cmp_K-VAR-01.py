# -*- coding: utf-8 -*-
"""K-VAR-01 (2–3 образи РІЗНИХ полюсів, а не одна безпечна медіана) — пакет
перестав замовляти полюс, якого пул не несе.

ДО ПРАВКИ: `pipeline.пакет_для_моделі` різав словник `ПОЛЮСИ_ОБРАЗУ` за числом
образів і нічого не питав у пулу. На `каталог_повний.xml` (сцена «офіс · 18 °C»,
варіантів=6) пакет оголошував ШІСТЬ полюсів, серед них «розрив» — «одна річ
навмисно поза палітрою», — а в пулі з 383 речей на гілці «розрив» стояв НУЛЬ: усі
383 були «ядро». Виконати таке замовлення можна одним способом — віддати ще одну
варіацію тієї самої середини, тобто рівно те, що правило зве провалом.
ПІСЛЯ: `composer.полюси_пулу` питає пул, пакет замовляє лише спроможні полюси, а
решту називає вголос у вимогах. Жодної нової константи: якір стоїть на
`виразність_героя`, колона — на кроці Munsell `step_min`, вузол і розрив — на
означеннях."""
import sys, pathlib, json, collections
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, composer as КМ, pipeline as PL

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
вх["варіантів"] = 6
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
h1 = json.loads(r["руки"]["1"])
пак = [p for p in B._КЕШ_ПАКЕТА.values() if p.get("кандидати")][0]
спром = КМ.полюси_пулу(пак["кандидати"])
гілки = collections.Counter(x.get("гілка") for п in пак["кандидати"].values() for x in п)
print("пул руки 1: %d речей, гілки %s" % (sum(гілки.values()), dict(гілки)))
print("словник полюсів коду: %d · замовлено в пакеті: %d"
      % (len(PL.ПОЛЮСИ_ОБРАЗУ), len(h1["полюси"])))
for ід, _ in PL.ПОЛЮСИ_ОБРАЗУ:
    с = спром.get(ід) or {}
    print("   %-16s %s · %s" % (ід, "ЗАМОВЛЕНО " if с.get("є") else "не замовлено",
                                (с.get("чому") or "")[:72]))
нема = [ід for ід, _ in PL.ПОЛЮСИ_ОБРАЗУ if not (спром.get(ід) or {}).get("є")]
рядок = next((в for в in h1["завдання"]["вхід"] if в.startswith("«полюси_недосяжні»")), None)   # збирач 25.09
print("рядок вимог про недосяжні полюси:", "НЕМА" if not рядок else рядок[:110], "·", h1.get("полюси_недосяжні"))
assert нема, "на цьому каталозі принаймні «розрив» недосяжний — інакше проба не міряє нічого"
assert рядок, "недосяжний полюс мусить бути названий, а не мовчки зниклий"
assert all(p["ід"] not in нема for p in h1["полюси"]), "замовлено полюс, якого пул не несе"
