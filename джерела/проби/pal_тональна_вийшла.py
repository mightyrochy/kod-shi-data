# -*- coding: utf-8 -*-
"""Тональна — одна схема на екрані й у «вийшла» (рядок 1403).

Екран: «один тон на всіх речах із маленькими кроками світлоти». ДО «вийшла» стояла на будь-якій
кольоровій речі (з 15 «так» 12 — одна сумка). ПІСЛЯ: тон схеми мусить нести велика річ; ціль
кольорової ролі темної основи не обрізається до нейтралі (`brief.колір_слота`). Запуск із `джерела`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import palettes as PAL, brief as Б, colorspace as cs, суд_від_моделі as СВ

дуга = (160.0, 184.0)
сп = {с: dict(роль=р, L=[5, 95], C=[14.0, 34.0], дуга_тону=дуга)
      for с, р in (("верх", "домінанта"), ("низ", "секундант"), ("взуття", "секундант"), ("сумка", "акцент"))}
сп["_схема"] = "тональна"
річ = lambda і, сл, L, C, h: {"id": і, "слот": сл, "lab": list(СВ._lab_з(L, C, h))}
сумка_лише = [річ("v", "верх", 85, 2, 80), річ("n", "низ", 25, 2, 260), річ("b", "сумка", 50, 30, 172)]
тон_на_верху = [річ("v", "верх", 70, 20, 170), річ("n", "низ", 45, 18, 175), річ("b", "сумка", 50, 30, 172)]
for назва, речі in (("нейтральні верх і низ + сумка тону", сумка_лише), ("верх і низ тону", тон_на_верху)):
    т = PAL.тон_тональної(речі, сп)
    зн = PAL.обіцянка_схеми(речі, сп)
    пов = PAL.повідомлення_схеми_жінці(речі, сп)
    print("%s: великих на тоні %d/%d · K-COL-03 %s · вийшла=%s" % (
        назва, т["великих_на_тоні"], т["великих_виміряно"], [з["заяви"][0]["code"] for з in зн] or "—",
        "так" if not пов else "ні"))
assert PAL.повідомлення_схеми_жінці(сумка_лише, сп) and PAL.обіцянка_схеми(сумка_лише, сп)
assert not PAL.повідомлення_схеми_жінці(тон_на_верху, сп) and not PAL.обіцянка_схеми(тон_на_верху, сп)

ціль, _ = Б.колір_слота(dict(L=[2, 18], C=[14.0, 34.0], дуга_тону=(110.0, 134.0)))
L, C, h = cs.lch(cs.hx(ціль))
print("ціль верху темної «хвої» (L 2–18, C 14–34): %s — L* %.0f C* %.0f (ДО #181d0e: C* 10)" % (ціль, L, C))
assert C >= 14, ціль
