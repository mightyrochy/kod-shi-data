# Рядок 184: тип брався з ПЕРШОГО ключа словника будь-де в «категорія + назва», тож
# прикметник перемагав іменник («Куртка джинсова» → джинси). Тип діє у веті, у пошуку
# за бажанням і в суді дрес-коду. Слово, що доти БУЛО типом, тримало казуальність речі,
# тож міряємо ще й СТЕЛЮ формальності: без перетину з модифікатором вона піднімалась у
# 346 речей на ≥ 2, і весілля 7–9 переставало бачити джинсову сукню як «рівень нижче».
import sys, os, importlib.util
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import feed, фід_каталог as ФК, фід_слот as НОВ, формальність as ФОРМ
_сп = importlib.util.spec_from_file_location(
    "до_фід_слот", os.environ.get("DO_FID_SLOT", "/tmp/184/до_фід_слот.py"))
СТАР = importlib.util.module_from_spec(_сп); _сп.loader.exec_module(СТАР)
кат = ФК._прочитати_каталог(feed.каталог_на_диску("каталог_повний.xml"), 0)["каталог"]
оф = lambda r: {"назва": r.get("назва"), "категорія": r.get("категорія"),
                "параметри": r.get("параметри") or {}}   # рядок оферти для класифікатора
тип = lambda м, r: м._тип_речі_обчислити(оф(r), r.get("слот"))
назва = lambda r: (r.get("назва") or "").lower()
стеля = lambda e: ФОРМ.інтервал_формальності(e)[1]
бажання = lambda м, ф: м._тип_речі_обчислити(
    {"назва": ф, "категорія": "", "параметри": {}}, м.слот({"назва": ф, "категорія": ""}))
чужий = lambda м: sum(1 for r in кат for пр in
                      [НОВ.предмет_типу(НОВ._re_тип.sub(" ", назва(r)), r.get("слот"))]
                      if пр is not None and тип(м, r) != пр[0])
спід = lambda м: sum(1 for r in кат if r.get("слот") == "низ"
                     and тип(м, r) == бажання(м, "джинси") and "спідниц" in назва(r))
курт = lambda м: sum(1 for r in кат if тип(м, r) == "куртка" and "джинс" in назва(r))
човн = lambda м: sum(1 for r in кат if r.get("слот") == "верх" and тип(м, r) == "човники")
# Стеля ДО — з типом, який давав старий код, і без модифікатора (його тоді не було).
до = lambda r, a: dict(r, тип=a, тип_модифікатор=None)
після = lambda r, b: dict(r, тип=b, тип_модифікатор=НОВ.тип_модифікатор(оф(r), r.get("слот")))
пара = [(стеля(до(r, a)), стеля(після(r, b)))
        for r in кат for a, b in [(тип(СТАР, r), тип(НОВ, r))] if a != b]
вище = sum(1 for х1, х2 in пара if х1 is not None and х2 is not None and х2 - х1 >= 2)
print("речей %d · змінили тип %d" % (len(кат), len(пара)))
print("тип ≠ типу предмета назви:            %4d → %4d" % (чужий(СТАР), чужий(НОВ)))
print("бажання «джинси»: спідниць у низу:    %4d → %4d" % (спід(СТАР), спід(НОВ)))
print("вето «куртка» ловить джинсових курток: %3d → %4d" % (курт(СТАР), курт(НОВ)))
print("тип «човники» у слоті «верх»:         %4d → %4d" % (човн(СТАР), човн(НОВ)))
print("стеля формальності вища на ≥ 2:        346 → %4d (винятки названі в PR)" % вище)
print("ВПАЛО %d" % (0 if чужий(НОВ) == спід(НОВ) == човн(НОВ) == 0
                    and курт(НОВ) == 22 and вище <= 24 else 1))
