# Рядок 187: `тип_речі` виробляв «мокасини», «балетки», «мюлі», «челсі», «ботфорти»,
# «уггі», «еспадрильї» ще з теми-10, а `інтервал_типу` про них не знав — (None, None).
# K-KOH-02/05 беруть речі ЛИШЕ з інтервалом, тож на весіллі 7–9 замшеві мокасини
# проходили МОВЧКИ. Сім смуг узято з тих, що вже стоять у таблиці, — нових чисел нема.
import sys, os, collections, importlib.util
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import feed, фід_каталог as ФК, фід_слот as ФС, формальність as ФН
_сп = importlib.util.spec_from_file_location(
    "до_формальність", os.environ.get("DO_FORM", "/tmp/187/до_формальність.py"))
ФД = importlib.util.module_from_spec(_сп); _сп.loader.exec_module(ФД)
СІМ = ("уггі", "еспадрильї", "балетки", "мюлі", "челсі", "мокасини", "ботфорти")
кат = ФК._прочитати_каталог(feed.каталог_на_диску("каталог_повний.xml"), 0)["каталог"]
оф = lambda r: {"назва": r.get("назва"), "категорія": r.get("категорія"), "параметри": r.get("параметри") or {}}
пари = [(r, ФС._тип_речі_обчислити(оф(r), "взуття")) for r in кат if r.get("слот") == "взуття"]
інт = lambda м, т: м.ТИП_ІНТЕРВАЛ.get(т)
print("взуття %d · з інтервалом %d → %d · сім типів: %s"
      % (len(пари), sum(1 for _, т in пари if інт(ФД, т)), sum(1 for _, т in пари if інт(ФН, т)),
         dict(collections.Counter(т for _, т in пари if т in СІМ))))
впало = sum(1 for т in СІМ if not інт(ФН, т)) + sum(1 for т in СІМ if інт(ФД, т))
def різані(м, смуга):                     # `композитор_придатні._поза_сценою`, допуск взуття 1.0
    lo, hi = смуга
    return [т for _, т in пари if інт(м, т) and (інт(м, т)[1] < lo - 1 or інт(м, т)[0] > hi + 1)]
for ім, смуга in (("весілля 7–9", (7, 9)), ("офіс 4–6", (4, 6)), ("прогулянка 2–4", (2, 4))):
    a, b = різані(ФД, смуга), різані(ФН, смуга)
    нові = collections.Counter(т for т in b if т in СІМ)
    print("  %-15s поза сценою %4d → %4d · нові зняття: %s" % (ім, len(a), len(b), dict(нові) or "—"))
    # ЗАЙВИХ ЗАБОРОН У ДЕННИХ СЦЕНАХ БУТИ НЕ МАЄ: смуги 3–5 і 4–6 лежать усередині них.
    впало += (len(b) != len(a)) if смуга != (7, 9) else (len(b) <= len(a))
# Те, що бачила тестувальниця: весілля гостею, замшеві мокасини — і тиша.
сцен = {"діапазон": (7, 9), "risk_posture": "neutral"}
сук = {"річ": "с1", "слот": "сукня", "назва": "Вечірня сукня в підлогу", "тип": "вечірня_сукня"}
мок = lambda т: {"річ": "в1", "слот": "взуття", "назва": "Мокасини замшеві", "тип": т}
д = ФД.формальність_образу([сук, мок("мокасини")], сцен)
п = ФН.формальність_образу([сук, мок("мокасини")], сцен)
print("весілля 7–9 · вечірня сукня + замшеві мокасини: знахідок %d → %d · %s"
      % (len(д), len(п), [z["правило"] for z in п]))
впало += len(д) + (0 if len(п) >= 2 else 1)
print("ВПАЛО %d" % впало)
