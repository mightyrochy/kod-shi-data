# -*- coding: utf-8 -*-
"""Приймальна проба Т-02: рука 1 — валідний ПАКЕТ_V1, і суд іде ТИМ САМИМ пулом.

Друкує ФАКТИ, а не «ок»: довжину пакета проти бюджету, число речей у пулі,
помилки схеми (має бути 0) і чи номер «#N·MM» з пакета резолвиться у суді в ту
саму річ. Друге важливе рівно тому, що з Т-02 правила лежать УСЕРЕДИНІ пакета:
бюджет міряє повний JSON, отже набір правил через довжину впливає на зріз пулу,
і `від_моделі` без тих самих правил судив би інший пул.
Запуск: PYTHONPATH=. python3 проби/пакет_v1.py
"""
import json
import bridge as B
import протокол as P

вх = json.load(open("стенд_вх.json"))
for варіантів in (1, 10):
    d = dict(вх, варіантів=варіантів)
    r = json.loads(B.виклик("запити", json.dumps(d, ensure_ascii=False)))
    рука = r["руки"]["1"]
    пакет = json.loads(рука)
    пом = P.перевірити(P.СХЕМИ["ПАКЕТ_V1"], пакет)
    речей = sum(len(v) for v in пакет["пул"].values())
    print("варіантів=%-2d довжина %6d (бюджет 120000) · речей %d · образів %d · полюсів %d · помилок схеми %d"
          % (варіантів, len(рука), речей, пакет["завдання"]["образів"],
             len(пакет["полюси"]), len(пом)))
    for x in пом[:5]:
        print("   помилка схеми:", x)
    print("   поля:", ", ".join(пакет.keys()),
          "· правил", len(пакет.get("правила") or []))
    # ТОЙ САМИЙ ПУЛ У СУДІ: беремо по одній речі ядра ЗА НОМЕРОМ з пакета і
    # шлемо їх текстом, як зробила б модель. `поза_кандидатами` мусить бути порожнє.
    ядро = [пакет["пул"][с][0]["н"] for с in ("верх", "низ", "взуття", "сумка")
            if пакет["пул"].get(с)]
    вм = json.loads(B.виклик("від_моделі", json.dumps(
        dict(d, текст_моделі="ОБРАЗ: " + ", ".join(ядро)), ensure_ascii=False)))
    print("   номерами %s → речей %d, поза кандидатами %s, знахідок %d"
          % (", ".join(ядро), len(вм.get("речі") or вм.get("ід") or []),
             вм.get("поза_кандидатами"), len(вм.get("знахідки") or [])))
