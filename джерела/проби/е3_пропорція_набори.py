"""Повний каталог для `верхнє_пропорція`: кожен верхній шар × класи низу × тіла."""
import gzip, json, os, pathlib


def тіла():
    """Чотири тіла: ширші стегна, ширші плечі, рівні, без входу для фронтального V."""
    import fit as Ф
    з = lambda п, с, **к: Ф.тіло(168.0, {"плечі": п, "груди": 92.0, "талія": 76.0, "стегна": с}, **к)
    return dict(стегна=з(90.0, 106.0, аксесуарні={"шия_см": 34.0}), плечі=з(104.0, 92.0, аксесуарні={"шия_см": 34.0}),
                рівні=з(98.0, 98.0, аксесуарні={"шия_см": 34.0}), без_входу=з(96.0, 98.0))


def набори():
    """(назва, функція, args) без моделі; низ — по одному на клас (крій, оверсайз)."""
    import feed as Ф
    import outfit as О
    import trace as Т
    кеш = pathlib.Path(os.environ['TMP']) / 'е3_каталог.json.gz'
    if not кеш.exists():
        каталог = Ф.база_прогону(Ф.каталог_на_диску('каталог_повний.xml'), ліміт_фото=0)['каталог']
        with gzip.open(кеш, 'wt', encoding='utf-8') as ф:
            json.dump(каталог, ф, ensure_ascii=False)
    with gzip.open(кеш, 'rt', encoding='utf-8') as ф:
        каталог = json.load(ф)
    верхи = [р for р in каталог if р.get('слот') == 'верхній_шар']
    класи = {}
    for р in каталог:
        if р.get('слот') in ('низ', 'сукня'):
            класи.setdefault((р['слот'], О.крій_речі(р), bool(р.get('оверсайз'))), р)
    print('каталог', len(каталог), 'верхів', len(верхи), 'класів низу', len(класи), flush=True)
    Т_ = тіла()
    for в in верхи:
        yield str(в['id']), 'обʼєм_пари', [[в]]
        for к, н in sorted(класи.items(), key=str):
            yield '%s+%s' % (в['id'], н['id']), 'обʼєм_пари', [[в, н]]
        for ім, т in Т_.items():
            yield '%s@%s' % (в['id'], ім), 'плечова_вісь', [[в], т]
            yield '%s@%s' % (в['id'], ім), 'фронтальний_V', [[в], т]
        Т.ЗАПИСИ.clear()
