# -*- coding: utf-8 -*-
"""Рядок 108: мета — поле СЦЕНАРІЮ зі слів жінки. Три фрази (про увагу / приховати / нічого)
→ паспорт `мета` + цитата, сценарій після шва, `людина.мета` і `чому_мети` пакета, і важіль
R-CHEV-08: вікно b* нейтралі-якоря (`palette.нейтраль_якір`, драп «золото») — ДО (паспорт
без поля) і ПІСЛЯ. Запуск із теки `джерела`: python3 проби/pasport_meta_108.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, pipeline as PL, міст_основи as MO, палітра_нейтраль as PN

вх = json.load(open("стенд_вх.json", encoding="utf-8"))
сц = dict(нагода="побачення", місце="ресторан_районний", година=19, темп_c=12)
ДРАП = dict(метал="золото", білий="вершковий")
ФРАЗИ = (("хочу, щоб на мене дивились — заявити про себе", "експресія"),
         ("не хочу привертати уваги, і щоб сховати живіт", "приховати"),
         ("побачення в ресторані о сьомій", "невідомо"))
for слова, від_моделі in ФРАЗИ:
    п = PL.паспорт_з_json(json.dumps(dict(подія=слова, нагода="побачення", мета=від_моделі), ensure_ascii=False), сц, слова)
    до = {k: v for k, v in п.items() if k not in ("мета", "мета_слова")}     # ДО: паспорт поля не мав
    print("«%s» → паспорт.мета=%s, мета_слова=%r" % (слова, п["мета"], п.get("мета_слова")))
    for мітка, пасп in (("ДО", до), ("ПІСЛЯ", п)):
        d = B._застосувати_паспорт(dict(вх, сценарій=dict(сц), паспорт=пасп))
        F, T, зріст, kw = B._збірка(d)
        л = MO._пакет(F, T, зріст, kw, None, "conventional", None, None, ДРАП)["людина"]
        я = PN.нейтраль_якір(F, слот="верх", драп=ДРАП, мета=л["мета"])
        print("  %-5s сценарій.мета=%-9s → людина.мета=%-9s вікно b* нейтралі [%s..%s] вага %.2f гармонізує=%s"
              % (мітка, kw.get("мета", "—"), л["мета"], я.get("b_min"), я.get("b_max"), я.get("вага_вікна", 0), я.get("гармонізує")))
        print("        чому_мети: %s" % л["чому_мети"][:150])
assert PL.паспорт_з_json(json.dumps(dict(мета="приховати")), сц, "x")["мета"] == "приховати"
assert PL.паспорт_з_json(json.dumps(dict(мета="statement")), сц, "x")["мета"] == "невідомо"   # чуже слово — не мета
