"""Міряє повноту її слів від ходів перекладача до дроту й показу; argv[1] — коміт ДО."""
import json, os, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import мовний_шар as М, паспорт_нагоди as ПН, пакет_моделі as ПМ, дріт_моделі as Д, руки_без_коду as Р
if len(sys.argv) > 1:
    for мод in (ПН, М):
        код = subprocess.check_output(["git", "show", sys.argv[1] + ":джерела/" + мод.__name__ + ".py"])
        exec(compile(код, мод.__file__, "exec"), мод.__dict__)
фрази = ["У залі завжди холодно", "Довго стоятиму в черзі", "Потім зайду до подруги",
         "Поїду громадським транспортом", "Візьму з собою книжку", "Після вечері буде фотосесія",
         "Сидітиму біля відчиненого вікна", "Хочу впізнати себе на фото", "Маю встигнути на останній потяг"]
п = {}
for фраза in фрази:
    п = М.паспорт_з_шару({"rest": фраза, "quotes": {"rest": фраза}}, {},
                       паспорт_досі=п, слова_ходу=фраза)["паспорт"]
читачі = [Д.випадок(ПМ.випадок_для_пакета(п, "", {})), Р.випадок_кодами(п, "", {})]
міри = [("решта в паспорті", len(п.get("решта", [])), len(фрази))]
міри += [("решта на дроті %d" % i, len(в.get("her_other_words", [])), len(фрази))
         for i, в in enumerate(читачі, 1)]
міри += [("слова дослівно на дроті %d" % i, int(в.get("her_other_words") == фрази), 1)
         for i, в in enumerate(читачі, 1)]
довге = "Зустріч з подругами у старовинній бібліотеці після презентації нашої нової книжки"
п = ПН.паспорт_з_json(json.dumps({"місце": "кафе", "місце_слова": довге, "подія": довге}), {}, "", шар=True)
міри.append(("місце у паспорті", len(п.get("місце_слова", "")), len(довге)))
шматки = ПН.паспорт_шматками_людині(п)
міри.append(("подія у показі", len(next(ш["текст"] for ш in шматки if ш["ключ"] == "подія")), len(довге)))
for поле, префікс in (("place_words", "place_words_without_place"), ("event", "event_without_scene")):
    п = М.паспорт_з_шару({поле: довге, "quotes": {поле: довге}}, {}, слова_ходу=довге)["паспорт"]
    рядок = next(р for р in п.get("не_взято_кодом", []) if р.startswith(префікс))
    міри.append(("повний діагноз " + поле, int(довге in рядок), 1))
for назва, факт, ціль in міри:
    print("%s: %s / %s" % (назва, факт, ціль))
sys.exit(any(факт != ціль for _, факт, ціль in міри))
