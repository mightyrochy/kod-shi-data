# -*- coding: utf-8 -*-
"""Розбір 3/8: що ПАКЕТ_V1 каже моделі про МІСЦЕ речі й про її КОЛІР.

Рішення власника: «модель сама знає, що джинси — низ: місце речі в образі їй не
прописувати». Проба міряє, скількома способами пакет усе-таки називає слот, і
поруч звіряє докстрінг `пакет_моделі._річ_пулу` («КОЛЬОРУ ТУТ НЕМА НАВМИСНО») з
тим, що річ справді несе.
Прогін: python3 проби/шлях_пул_слот_і_колір.py
"""
import json, os, re, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ)
ФАЙЛ = os.path.join(os.path.dirname(ТУТ), "аудит", "тести", "власник_2026-09-25",
                    "verdykty-0phxvk-2026-09-25-2012.json")
пак = {}
for пр in json.load(open(ФАЙЛ, encoding="utf-8"))["прогони"]:
    for в in пр["вердикти"]:
        for c in ((в.get("етапи") or {}).get("виклики") or []):
            т = (c.get("запит") or {}).get("текст") or "" if isinstance(c.get("запит"), dict) else ""
            if т.startswith("{") and c.get("крок") == "складання" and json.loads(т).get("пул"):
                пак = json.loads(т)
пул = пак["пул"]
речі = [r for с in пул for r in пул[с]]
слоти = list(пул)
print("слот названо КЛЮЧЕМ пулу: %d слотів — %s" % (len(слоти), ", ".join(слоти)))
print("поле «слот» усередині речі: %d речей із %d" % (sum(1 for r in речі if "слот" in r), len(речі)))
print("поле «може_стати» (інші слоти речі): %d речей" % sum(1 for r in речі if r.get("може_стати")))
for i, в in enumerate(пак["завдання"].get("вимоги") or []):
    if "слот" in в:
        print("  вимога %d про слоти: %s" % (i, в[:120]))
print("колір: %d речей, hex: %d, сім_я: %d, у_дузі: %d"
      % (*[sum(1 for r in речі if r.get(k) is not None) for k in ("колір", "hex", "сім_я", "у_дузі")],))
код = open(os.path.join(ТУТ, "пакет_моделі.py"), encoding="utf-8").read()
тіло = код[код.index("def _річ_пулу"):код.index("def випадок_для_пакета")]
а = тіло.index('"""') + 3
док = тіло[а:тіло.index('"""', а)]
print("докстрінг _річ_пулу про колір: %s"
      % " ".join(re.sub(r"\s+", " ", док[док.index("КОЛЬОРУ"):]).split()[:20]))
