"""K-PAL-01 — правило породження палітри діє В ПУЛІ, не лише у сліді.

Корпус (тема-2:1833): палітра — область простору, що ПОДІЛЯЄ домінанту людини,
і вона доходить до каталогу рядками запиту (`palette.запит_у_фід`). Проба питає
пул: чи кожну хроматичну річ ядра взяв КОЛЬОРОВИЙ рядок її слота — предикатом
самого продукту (`feed.підходить` для виміряного кольору, `частка_вікна`+
`описує_річ` для кольору-словом). Нейтральний рядок чисельника не дає: саме ним
річ їхала в пул блідим краєм (86 із 97). Вимір — у `pal_вимір.частка_у_вікнах`.
ДО ПЕРШОЇ ПРАВКИ (17.09, стенд, гілка 0, схема «тональна», каталог_повний): 4.1 %.
ПЕРЕМІРЯНО 19.09 ПІСЛЯ #126: проба питала глобальне вікно `палітра_практична`
(L 55–95) замість вікна слота, і вимір із фото на в'язаних штанах (L 31.9, вікно
секунданта 30–39) читався поломкою — 66.7 % на здоровому пулі. Чинний контракт —
рядки запиту; на них 100 %. Що проба ще ловить: знята з добору перевірка роду
рядка (`feed.описує_річ`) дає 10 із 26 — 38.5 %.
Запуск із теки `джерела`: `python3 проби/pal_K-PAL-01.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вимір as В

for намір in ("conventional", "statement"):
    кандидати, кат, спец, запити = В.пул_стенда(гілка=0, намір=намір)
    у_ядрі, ядро, по_слотах, запасом = В.частка_у_вікнах(кандидати, кат, спец, запити)
    у_всіх, усі, _, _ = В.частка_у_вікнах(кандидати, кат, спец, запити, гілка=None)
    частка = 100.0 * у_ядрі / max(1, ядро)
    кольорових = sum(1 for q in запити if not q.get("нейтраль") and not q.get("метал"))
    print("намір «%s» · схема «%s» · рядків запиту %d, з них кольорових %d, металевих %d"
          % (намір, спец.get("схема"), len(запити), кольорових,
             sum(1 for q in запити if q.get("метал"))))
    for слот, (ок, n) in sorted(по_слотах.items(), key=lambda kv: -kv[1][1]):
        print("     %-14s %3d/%3d" % (слот, ок, n))
    print("  ФАКТ · ядро: не-нейтралей і не-металу %d, узятих кольоровим рядком слота %d"
          " — %.1f %% (з них лише рядком-гарантією %d)" % (ядро, у_ядрі, частка, запасом))
    print("        поза ядром (гілки «на межі» / «розрив» — вихід за палітру навмисний): %d із %d"
          % (усі - ядро, усі))
    assert частка >= 90.0, "частка %.1f %% — рядки палітри пул не тримають" % частка
