"""K-PAL-01 — правило породження палітри діє В ПУЛІ, не лише у сліді.

Корпус (тема-2:1833): палітра — область простору, що ПОДІЛЯЄ домінанту людини;
код рахував вікна (`palettes._вікно_L`, `_вікно_C`, `_дуги_сімей`) і клав їх у фід.
ДО ПРАВКИ (стенд, гілка 0, схема «тональна» 160–184°, каталог_повний): у пулі 97
не-нейтралей, у вікнах людини й дузі схеми — 4, тобто 4.1 %. Три течі:
  · рядок-нейтраль пускав хроматичну річ її блідим краєм (`частка_вікна` > 0),
    а в пакет річ їхала своїм представником — 86 із 97 (`feed.описує_річ`);
  · дуга сім'ї їхала в фід ЦІЛОЮ, якщо торкалась дуги схеми запасом 20°: «синя»
    (195–240°) віддавала всі 29 своїх речей у дугу 160–184° (`palette._перетин_дуг`);
  · «нейтраль» мала в системі ДВА означення — `колір_образу.нейтраль` і копія в
    `pipeline`, і темне нейві було нейтраллю для добору й кольором для суду.
Запуск із теки `джерела`: `python3 проби/pal_K-PAL-01.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вимір as В

for намір in ("conventional", "statement"):
    кандидати, кат, спец, запити = В.пул_стенда(гілка=0, намір=намір)
    П = спец["палітра_практична"]
    у_ядрі, ядро, по_слотах = В.частка_у_вікнах(кандидати, кат, спец, гілка="ядро")
    у_всіх, усі, _ = В.частка_у_вікнах(кандидати, кат, спец, гілка=None)
    частка = 100.0 * у_ядрі / max(1, ядро)
    print("намір «%s» · схема «%s» · вікно палітри: світлота %.0f–%.0f, хрома %.0f–%.0f · метал %s"
          % (намір, спец.get("схема"), П["вікна"]["L"][0], П["вікна"]["L"][1],
             П["вікна"]["C"][0], П["вікна"]["C"][1], П["метал"]))
    for слот, (ок, n) in sorted(по_слотах.items(), key=lambda kv: -kv[1][1]):
        print("     %-14s %3d/%3d" % (слот, ок, n))
    print("  ФАКТ · ядро: не-нейтралей і не-металу %d, у вікнах палітри й дузі схеми %d — %.1f %%"
          % (ядро, у_ядрі, частка))
    print("        поза ядром (гілки «на межі» / «розрив» — вихід за палітру навмисний): %d із %d"
          % (усі - ядро, усі))
    print("        рядків запиту %d, з них обрізаних дугою схеми %d, металевих %d"
          % (len(запити), sum(1 for q in запити if q.get("дуга_до_обрізання")),
             sum(1 for q in запити if q.get("метал"))))
    assert частка >= 90.0, "частка %.1f %% — вікна палітри пул не тримають" % частка
