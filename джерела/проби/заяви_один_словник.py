"""ПРОБА рядка 157 (Ч-7, 27.09.2026, аудит/ПРОДУКТ.md п.12): словник ЗАЯВ ОДИН і англійський —
код не тримає готового українського речення для жінки, а значення коду несе ще й опис
своїх `values`, щоб модель уміла вставити число чи назву. ДРУКУЄ: скільки кодів, скільки
значень із кирилицею (має бути 0), скільки значень на «ти» чи наказом (готова фраза —
теж 0), скільки несуть опис `values`, і чи лишився другий словник.
ЗАПУСК (тека `джерела`): python3 проби/заяви_один_словник.py"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import внутрішня_мова as ВМ

КИРИЛИЦЯ = re.compile(r"[А-Яа-яІіЇїЄєҐґ]")
# «ти», «твій» і наказ — ознаки ГОТОВОЇ фрази для жінки, а не опису для моделі
НА_ТИ = re.compile(r"\b(ти|тебе|тобі|тобою|тво[яєїюго]\w*|твій)\b", re.I)
НАКАЗ = re.compile(r"\b(постав|візьми|бери|оживи|просоч|назви|дай|зніми|додай|перевір|"
                   r"обери|лиши|тримай|зроби|скажи|спитай|поклади|уникай|носи|вдягни)\b", re.I)

значення = ВМ.ЗАЯВИ
кир = sorted(к for к, т in значення.items() if КИРИЛИЦЯ.search(т))
фрази = sorted(к for к, т in значення.items() if НА_ТИ.search(т) or НАКАЗ.search(т))
з_values = [к for к, т in значення.items() if "(values:" in т]
симв = sum(len(т) for т in значення.values())

print("кодів заяв: %d · символів у значеннях: %d (у середньому %.0f на код)"
      % (len(значення), симв, симв / len(значення)))
print("значень із кирилицею: %d %s" % (len(кир), кир[:5]))
print("значень-фраз для жінки (на «ти» чи наказом): %d %s" % (len(фрази), фрази[:5]))
print("значень з описом своїх `values`: %d із %d" % (len(з_values), len(значення)))
print("другий словник (`ЗАЯВИ_EN`) існує: %s" % hasattr(ВМ, "ЗАЯВИ_EN"))
_к = ["too_few_items", "needs_third_piece"]
print("те саме визначення читають обидві моделі: %s"
      % (ВМ.визначення_заяв(_к) == {к: значення[к] for к in _к}))
print("ФАКТ: %s" % ("словник ЗАЯВ один і англійський — речення жінці пише мовна модель"
                    if not (кир or фрази or hasattr(ВМ, "ЗАЯВИ_EN"))
                    else "словник ЗАЯВ ще несе фразу для жінки або двійника"))
