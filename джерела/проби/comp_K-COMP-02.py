"""K-COMP-02 (якір першим: образ веде ОДНА виразна річ):
`python3 проби/comp_K-COMP-02.py`.

ЗВЕДЕННЯ ДАЄ «БЕЗ СЛІДУ», І ЦЕ ВИМІР БАТАРЕЇ, А НЕ ПРАВИЛА: емітент
(`pipeline.різноманітність`) судить НАБІР образів і мовчить на одному —
«без героя» й «з двома героями» є твердженнями про набір. Батарея гейта подає один
образ, тому правило в ній не могло вийти ніколи.
ЩО ПОКАЗУЄ ПРОБА: три образи від моделі одним викликом дають рядок K-COMP-02 у
`вердикт.набір`, і він поіменно називає ті образи, у яких виразної речі нема."""
import sys, pathlib, json
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import feed as Ф, bridge as B

вх = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml"); вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
за = {}
for c in кат: за.setdefault(c.get("слот"), []).append(c)
взяті, образи = set(), []
for i in range(3):
    речі = []
    for сл in ("верх", "низ", "взуття"):     # одна річ не може стояти у двох слотах
        c = next(c for c in за[сл] if c["id"] not in взяті)
        взяті.add(c["id"]); речі.append(c["id"])
    образи.append({"ід": "о%d" % (i + 1), "речі": речі})
print("образів у наборі:", len(образи))
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=json.dumps(
    {"версія": "1", "образи": образи}, ensure_ascii=False)), ensure_ascii=False)))
наб = (вм.get("вердикт") or {}).get("набір") or {}
print("герой:", json.dumps(наб.get("герой"), ensure_ascii=False))
з = next((z for z in (наб.get("знахідки") or []) if z["правило"] == "K-COMP-02"), None)
print("K-COMP-02:", "НЕМА" if not з else
      "%s %.2f · %s · речі %s" % (з["сила"], з["сила_нп"], з["суть"][:52], з["речі"]))
assert з, наб
