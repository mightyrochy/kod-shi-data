# -*- coding: utf-8 -*-
"""Приймальна проба Т-06: виклики 3 і 4 говорять схемами, а не прозою.

Друкує ФАКТИ на живому стенді: що в промпті вибору (обʼєкт ВЕРДИКТ_V1 із
`завдання.відповідь="ВИБІР_V1"`, 0 кодів правил, 0 рядків «── образ»); як читається
ВИБІР_V1 (обраний образ id-ами; `обрано` невідомого ід → `помилка_формату` і названий
запасний образ); що в ОПИС_V1 (номери речей, номери їхніх фото, укладка); як
читається ОПИС_ВІДПОВІДЬ_V1 (проза окремо, річ із чужим фото — id, без «текст» —
повторний виклик). Рядка «як доти» тут нема: прозових промптів уже нема, і
порівняння стоїть у тілі коміта.
Запуск із теки `джерела`: PYTHONPATH=. python3 проби/вибір_опис_v1.py
"""
import json, re
import bridge as B, протокол as P

вх = json.load(open("стенд_вх.json"))
d0 = dict(вх, сценарій=dict(нагода="вечірка", місце="ресторан", година=19, темп_c=18,
                            дрес_код="cocktail"), випадок="коктейль, ресторан, 19:00")
міст = lambda **kw: json.loads(B.виклик("від_моделі", json.dumps(dict(d0, **kw), ensure_ascii=False)))
пак = json.loads(json.loads(B.виклик("запити", json.dumps(d0, ensure_ascii=False)))["руки"]["1"])
# ── ОБРАЗИ ПОВНІ, ЯК ЇХ ВИМАГАЄ СУД (18.09.2026, після #55) ──────────────────
# Доти образ складався з верху, низу, взуття й сумки. Після повноти образу
# (взуття і сумка обов'язкові, ≥ 5 речей, із сукнею ≥ 4) і гейта K-KOH-05
# («cocktail просить сукню від коліна до міді») такий образ блокується, обране
# «о2» давало 0 речей у суді, і проба падала на `речі[-1]`. Тут образи — сукня,
# верхній шар, взуття, сумка, прикраса, — і обирається ПЕРШИЙ, який суд пропускає
# (структура ок, жодної знахідки регістру «гейт»); хто заблокований і чим — факт.
# Речі — з рядків пулу, які самі кажуть, що пройдуть суд: `у_дузі` (K-PAL-03,
# дуга схеми — гейт) і для сукні `довжина` коліно/литка (K-KOH-05 для cocktail).
СЛОТИ = ("сукня", "верхній_шар", "взуття", "сумка", "прикраси")
годиться = lambda с, р: р.get("у_дузі") is not False and (с != "сукня" or р.get("довжина") in ("коліно", "литка"))
речі_слота = {с: [р["н"] for р in (пак["пул"].get(с) or []) if годиться(с, р)] for с in СЛОТИ}
print("придатних рядків пулу:", {с: len(v) for с, v in речі_слота.items()})
образ = lambda k: [речі_слота[с][k % len(речі_слота[с])] for с in СЛОТИ if речі_слота[с]]
в2 = міст(ітерація=2, текст_моделі=json.dumps(dict(версія="1", образи=[
    dict(ід="о%d" % (k + 1), підпис="образ %d" % k, речі=образ(k)) for k in range(6)]),
    ensure_ascii=False))
пр3, над = в2["промпт_лише_вибору"], в2["вибір_над"]
гейт = lambda о: [z["правило"] for z in (о.get("знахідки") or []) if z.get("регістр") == "гейт"]
прохідні = [о["ід"] for о in над["образи"] if (о.get("структура") or {}).get("ок") and not гейт(о)]
print("образів %d · проходять суд: %s · блоковані: %s" % (len(над["образи"]), прохідні or "жодного",
      ["%s: %s" % (о["ід"], [б["код"] for б in (о.get("структура") or {}).get("блокери") or []] + гейт(о))
       for о in над["образи"] if о["ід"] not in прохідні][:3]))
assert прохідні, "жоден із шести образів не проходить суд — проба не має чого обрати"
обр = прохідні[0]
print("промпт вибору: %d символів · завдання.відповідь=%s · образів %d · кодів правил %d · «── образ» %d"
      % (len(пр3), json.loads(пр3)["завдання"]["відповідь"], len(над["образи"]),
         len(re.findall(r"\b[KR]-[A-Z]{2,6}-\d{2}\b", пр3)), пр3.count("── образ")))

вибір = lambda об: міст(ітерація=2, відповідь="ВИБІР_V1", вибір_над=над,
                        текст_моделі=json.dumps(об, ensure_ascii=False))
в3 = вибір(dict(версія="1", обрано=обр, чому="найкраще для неї"))
вб = в3["вибір"]
print("ВИБІР_V1 «%s»: обрано %s · речей у суді %d · підпис «%s» · помилок %d · замінено %s"
      % (обр, вб["обрано"], len(в3.get("речі") or []), вб["підпис"], len(вб["помилки"]), вб["замінено"]))
х = вибір(dict(версія="1", обрано="о9"))["вибір"]
print("ВИБІР_V1 «о9» (нема такого): «%s» · повторний виклик «%s» · запасний образ %s, речей %d"
      % ((х["помилки"] or [{}])[0].get("що", "")[:58], json.loads(х["повторний_виклик"])["помилка"],
         х["замінено"], len(х["ід"])))

оп = json.loads(B.виклик("опис", json.dumps(dict(d0, речі=вб["ід"], підпис=вб["підпис"],
                                                 номери=вб["номери"], образ=вб["обрано"]),
                                            ensure_ascii=False)))
об = оп["опис"]
print("ОПИС_V1: речей %d · номери %s · фото %d · фото_номери %s · укладка %d · вимог %d · помилок схеми %d"
      % (len(об["образ"]["речі"]), [р["н"] for р in об["образ"]["речі"]][:3], len(оп["фото"]),
         [р.get("фото_номери") for р in об["образ"]["речі"]][:3], len(об.get("укладка") or []),
         len(об["завдання"]["вимоги"]), len(P.перевірити(P.СХЕМИ["ОПИС_V1"], об))))

опис4 = lambda о: міст(ід=вб["ід"], ітерація=2, відповідь="ОПИС_ВІДПОВІДЬ_V1",
                       текст_моделі=json.dumps(о, ensure_ascii=False))["опис"]
о1 = опис4(dict(версія="1", текст="Спідниця й блуза в одному тоні тримають вертикаль.",
                як_носити=["заправити блузу спереду"],
                фото_не_те=[об["образ"]["речі"][-1]["н"]]))
print("ОПИС_ВІДПОВІДЬ_V1: текст %d символів · як_носити %d · фото_не_те %s → id %s · повторний виклик %s"
      % (len(о1["текст"]), len(о1["як_носити"]), о1["фото_не_те"], о1["фото_не_ті"],
         о1.get("повторний_виклик") is not None))
о2 = опис4(dict(версія="1", як_носити=["заправити блузу"]))
print("без «текст»: помилка «%s: %s» · повторний виклик просить %s"
      % (о2["помилки"][0]["де"], о2["помилки"][0]["що"],
         json.loads(о2["повторний_виклик"])["відповідь"]))
