"""Корінь Е2-частина-дня, крок 2 (а): записані перші ходи розмови крізь шов без моделі — що з часу дня несе
`паспорт_нагоди`: паспорт, виміри, нагода для правил (`з_показу`), стан поради, вечірні теми й шматки шапки картки.
argv[1] — корінь дерева коду (типово — це); останній рядок — підсумок."""
import sys, os, json, glob, warnings
warnings.filterwarnings("ignore")
ТУТ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(sys.argv[1] if len(sys.argv) > 1 else ТУТ, "джерела"))
import мовний_шар as М, паспорт_нагоди as ПН
лік = dict(записів=0, година_паспорта=0, година_виміру=0, година_нагоди=0, година_поради=0, пора_паспорта=0,
           пора_нагоди=0, вечірні_теми=0, вечірні_теми_низький=0, шматок_пори=0, шматок_години=0, виняток=0)
for ф in sorted(glob.glob(os.path.join(ТУТ, "аудит/**/VIDPOVIDI/seed*_01_мовний_шар_хід_розмови.txt"), recursive=True)):
    т = open(ф, encoding="utf8", errors="replace").read().split("── ВІДПОВІДЬ", 1)[-1]
    т, ім = т[т.find("{"):т.rfind("}") + 1], os.path.relpath(ф, ТУТ).replace("/VIDPOVIDI/seed", " s")[:-30]
    try:
        р = М.прийняти_розмову(т)
        п = М.паспорт_з_шару(р["внутрішня"], {}, частини=р.get("частини"))["паспорт"]
        н = ПН.з_показу({}, п)[0]
        ст, теми = ПН.стан_для_поради(н, п, ""), ПН.порада_коду(dict(н), п, всі=True)
        ш, тн = ПН.паспорт_шматками_людині(п), ПН.порада_коду(dict(н), п, всі=True, контраст="низький")
    except Exception as e:                                      # запис не JSON — рядок, не падіння
        лік["виняток"] += 1
        print(ім, "| виняток", type(e).__name__)
        continue
    вт, втн = (sorted(x for x, _ in т if x in ("мета", "макіяж")) for т in (теми, тн))
    for к, умова in (("записів", 1), ("година_паспорта", п.get("година") is not None),
                     ("година_виміру", (п.get("виміри") or {}).get("hour") is not None),
                     ("година_нагоди", н.get("година") is not None), ("година_поради", ст.get("година") is not None),
                     ("пора_паспорта", п.get("пора") not in (None, "", [])), ("пора_нагоди", н.get("пора") not in (None, "")),
                     ("вечірні_теми", bool(вт)), ("вечірні_теми_низький", bool(втн)),
                     ("шматок_пори", any(x["ключ"] == "пора" for x in ш)),
                     ("шматок_години", any(x["ключ"] == "година" for x in ш))):
        лік[к] += bool(умова)
    print(ім, "| паспорт година=%s хв=%s пора=%s | нагода година=%s пора=%s | вечірні теми=%s (низький контраст %s)"
          " | шматки=%s" % (
        п.get("година"), п.get("хвилини"), п.get("пора"), н.get("година"), н.get("пора"), вт, втн,
        [(x["ключ"], x["текст"]) for x in ш if x["ключ"] in ("пора", "година")]))
print("підсумок:", json.dumps(лік, ensure_ascii=False))
