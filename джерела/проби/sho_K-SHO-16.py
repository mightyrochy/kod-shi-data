# -*- coding: utf-8 -*-
"""K-SHO-16 (вартість носіння каблука росте з тривалістю, а не з порогом).

Аудит числив правило «без сліду». Вимір показує інше: код цілий, а мовчав він
через СЦЕНУ. `вартість_носіння` вмикається лише тоді, коли сценарій несе
тривалість або поверхню, — обидві властивості НАГОДИ, не речі, і стенд їх не
подавав. Вхід речі при цьому в каталозі є й широкий: `каблук_см` стоїть на
1 194 парах із 2 096 (57.0 %).
Проба друкує обидва стани тієї самої пари: без тривалості — «питання» черги
(K-END-01), із тривалістю й поверхнею — вартість у `вердикт.образи[0].знахідки`."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
вз = [c for c in кат if c.get("слот") == "взуття"]
пара = max(вз, key=lambda c: c.get("каблук_см") or 0)
сукня = next(c for c in кат if c.get("слот") == "сукня")
сумка = next(c for c in кат if c.get("слот") == "сумка")
print("взуття в пакеті %d · із `каблук_см` %d (%.1f %%)"
      % (len(вз), sum(1 for c in вз if c.get("каблук_см")), 
         100.0 * sum(1 for c in вз if c.get("каблук_см")) / len(вз)))
print("пара «%s» · каблук %.1f см" % (пара["назва"][:42], пара["каблук_см"]))
for сцена in (dict(), dict(тривалість_год=9, поверхня="бруківка")):
    d = dict(вх, сценарій=dict(вх["сценарій"], **сцена),
             ід=[сукня["id"], пара["id"], сумка["id"]])
    зн = ((json.loads(B.виклик("від_моделі", json.dumps(d, ensure_ascii=False))
           ).get("вердикт") or {}).get("образи") or [{}])[0].get("знахідки") or []
    р = next((z for z in зн if z.get("правило") == "K-SHO-16"), None)
    print("сцена %-34s → K-SHO-16: %s"
          % (сцена or "без тривалості й поверхні",
             "нема (вхід нагоди — черга, не дані)" if not р else
             "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:50])))
