"""Звірити знахідки принтів двох знімків (каталог чи гейти); друк таблиць сирих і ефективних змін ваги."""
import collections, gzip, json, sys

ОЧІКУВАНІ = {('R-PRN-04', 0.2, 0.25)}   # літерал без джерела → вага категорії hint (паспорт кореня)


def main():
    """Склад, сила й `блокує` тотожні; ефективні зміни — лише названі в ОЧІКУВАНІ."""
    def читати(шлях):
        with gzip.open(шлях, 'rt', encoding='utf-8') as ф:
            д = json.load(ф)
        return д['записи'] if isinstance(д, dict) else д
    до, після = map(читати, sys.argv[1:3])
    assert len(до) == len(після), (len(до), len(після))
    сирі, ефективні = collections.Counter(), collections.Counter()
    for д, п in zip(до, після):
        assert д[:7] == п[:7], (д, п)
        if д[7] != п[7]:
            сирі[д[2], д[5], д[7], п[7]] += 1
        if д[8] != п[8]:
            ефективні[д[2], д[8], п[8]] += 1
    print('знахідок', len(до), '— склад, сила, блокує тотожні; сирих змін', sum(сирі.values()),
          'ефективних', sum(ефективні.values()))
    print('| правило | сила | сира ДО | сира ПІСЛЯ | кількість |\n|---|---|---|---|---|')
    for (пр, с, а, б), н in sorted(сирі.items(), key=str):
        print('| %s | %s | %s | %s | %d |' % (пр, с, а, б, н))
    print('| правило | ефективна ДО | ефективна ПІСЛЯ | кількість |\n|---|---|---|---|')
    for (пр, а, б), н in sorted(ефективні.items(), key=str):
        print('| %s | %s | %s | %d |' % (пр, а, б, н))
    assert set(ефективні) <= ОЧІКУВАНІ, set(ефективні) - ОЧІКУВАНІ


if __name__ == '__main__':
    main()
