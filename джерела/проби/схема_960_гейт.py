# -*- coding: utf-8 -*-
"""СХЕМА-960: пропуск сім'ї схеми на великих речах — гейт лише тоді, коли схему обрала ВОНА.

Той самий образ (бордова сукня + сірий жакет; бірюзовий верх є в пулі) судиться тричі —
різниця лише в `межа_людини` (хто обрав схему: вона / стилістка / не питали). Друкує
регістр, силу й річ, яку код-ремонт має замінити. Запуск із `джерела`:
`python3 проби/схема_960_гейт.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import colorspace as cs, палітра_схеми as ПС

сім = [dict(роль="домінанта", дуга=[13.2, 49.2]), dict(роль="секундант", дуга=[193.2, 229.2])]
кат = {"сукня-бордо": dict(id="сукня-бордо", слот="сукня", lab=cs.hx("#6e2a2c")),
       "жакет-сірий": dict(id="жакет-сірий", слот="верх", lab=cs.hx("#8a8a88")),
       "блуза-бірюза": dict(id="блуза-бірюза", слот="верх", lab=cs.hx("#2f8a99"))}
спец = {"_поверхні": "великі", "_сім_ї": сім, "_схема": "приглушена_комплементарна"}
речі = [кат["сукня-бордо"], кат["жакет-сірий"]]
пул = {"верх": [кат["блуза-бірюза"]], "сукня": [кат["сукня-бордо"]]}
for хто, межа in (("вона", True), ("стилістка", False), ("не питали", None)):
    з = ПС.обіцянка_великих(речі, спец, кат, пул, None, межа_людини=межа)[0]
    print("ФАКТ · схему обрала %-9s → %s %.2f · %s · речі=%s" % (хто, з["сила"], з["сила_нп"], з["регістр"], з["речі"]))
    assert (з["регістр"] == "гейт") == (межа is True), з
    assert межа is not True or з["речі"] == ["жакет-сірий"], з
# брак асортименту: бірюзи в пулі нема — гейта нема навіть для її схеми
з = ПС.обіцянка_великих(речі, спец, кат, {"сукня": [кат["сукня-бордо"]]}, None, межа_людини=True)[0]
print("ФАКТ · вона, сім'ї в пулі нема → %s %.2f · %s" % (з["сила"], з["сила_нп"], з["регістр"]))
assert з["регістр"] != "гейт", з
