"""Справжній міст: переставлений ремонт зберігає кандидата, полюс та адресований хід."""
import pathlib, sys, json
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import os
os.chdir(sys.path[0])
import bridge as Б, feed as Ф, дріт_моделі as Д, протокол as П

def main():
    """Простежити два образи крізь складання, суд і переставлений ремонт без моделі."""
    вх = dict(json.loads(pathlib.Path("стенд_вх.json").read_text(encoding="utf-8")),
              каталог=Ф.каталог_на_диску("каталог_повний.xml"), пакети=1, сід=3, варіантів=2, ремонт_варіантів=2)
    def виклик(дія, **дані):
        """Викликати той самий міст, що обробляє відповідь стилістки."""
        return json.loads(Б.виклик(дія, json.dumps(dict(вх, **дані), ensure_ascii=False)))
    пул = виклик("запити")["пакети"]["1"]["пул"]
    образи = [dict(ід="о%d" % (i+1), полюс=П.ПОЛЮСИ[i],
                    речі=[пул[с][i % len(пул[с])]["н"] for с in ("верх", "низ", "взуття", "сумка")]) for i in range(2)]
    перший = виклик("від_моделі", текст_моделі=json.dumps(dict(версія="1", образи=образи), ensure_ascii=False))["вердикт"]
    адресат, знахідка = next((о, з) for о in перший["образи"] for з in о["знахідки"]
                             if з.get("регістр") == "репліка" and з.get("речі"))
    for о in образи:
        if о["ід"] == адресат["ід"]:
            о["свідомо"] = [dict(річ=знахідка["речі"][0], знахідка=знахідка["ід"],
                                 чому="Свідомо лишаю цей акцент заради задуму.")]
        о.pop("полюс")
    другий = виклик("від_моделі", текст_моделі=json.dumps(dict(версія="1", образи=образи[::-1]), ensure_ascii=False),
                    попередній_вердикт=перший, ітерація=2)["вердикт"]
    assert [о["ід"] for о in другий["образи"]] == ["о2", "о1"]
    assert [о["полюс"] for о in другий["образи"]] == [П.ПОЛЮСИ[1], П.ПОЛЮСИ[0]]
    обр = next(о for о in другий["образи"] if о["ід"] == адресат["ід"])
    assert any(с.get("знахідка") == знахідка["ід"] and с.get("чому") for с in обр.get("свідомі") or [])
    дріт = Д.вердикт(П.вердикт_на_дріт(другий), вибір=True)
    assert all(о["your_outfit"].get("pole") for о in дріт["verdict"])
    assert any(о.get("your_declared") for о in дріт["verdict"])
    print("Ремонт о2→о1: ід і полюси збережено; ід знахідки та причина дійшли до вибору")

if __name__ == "__main__":
    main()
