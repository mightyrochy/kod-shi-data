# -*- coding: utf-8 -*-
"""ФІГ-600, рядок 600: чи доходить верхній шар до геометрії посадки і чи судить K-SIL-02 його лінію.
Живий міст `від_моделі`, 6 сцен `стенд_знімок`: кожен верхній шар пулу сцени + перший низ + перше взуття.
`fit.поділ_образу` обгорнуто лише для виміру (річ шукається ЗА ID: міст може перенести її в слот «верх»).
Друкує: образів · верх_см верхнього шару · без довжини · K-SIL-02 на його лінії · K-SIL-02 будь-чия лінія ·
«утримано». Запуск із теки `джерела`: python3 проби/фіг600_верхній_шар_поділ.py  (≈4 хв)"""
import sys, os, json, collections
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge as B, feed as Ф, fit as ПС, стенд_знімок as СЗ
КАТ, База, ЖУР = Ф.каталог_на_диску("каталог_повний.xml"), json.load(open("стенд_вх.json", encoding="utf-8")), []
_о = ПС.поділ_образу
def _п(t, речі, *a, **k):
    з = _о(t, речі, *a, **k); ЖУР.append((речі, з)); return з
ПС.поділ_образу = _п
Z, сцени = collections.Counter(), collections.defaultdict(set)
for назва, сцен in СЗ.СЦЕНАРІЇ.items():
    вх = dict(База, каталог=КАТ, сценарій=сцен, випадок=назва)
    пул = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["кандидати"]
    for о in пул.get("верхній_шар") or []:
        ЖУР.clear()
        відп = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=[о["id"], пул["низ"][0]["id"], пул["взуття"][0]["id"]]), ensure_ascii=False)))
        зв = [з for з in відп.get("знахідки") or [] if isinstance(з, dict)]
        Z["образів"] += 1
        речі, зн = ЖУР[-1] if ЖУР else ([], [])
        р = next((x for x in речі if x["id"] == о["id"]), None)
        Z["верх_см верхнього шару є"] += bool(р and р.get("верх_см") is not None)
        Z["без довжини (дефолт слота)"] += bool(р and р.get("край_джерело") == "дефолт слота")
        s2 = [x for x in зн if x["правило"] == "K-SIL-02" and x.get("сила") != "утримано"]   # вердикти без «утримано»
        Z["K-SIL-02 на лінії верхнього шару"] += any(о["id"] in x["речі"] for x in s2)
        Z["K-SIL-02 виходить (будь-чия лінія)"] += bool(s2)
        if s2: сцени[назва].add(о["id"])
        Z["K-SIL-02 з діагностика.шари_без_довжини"] += any((x.get("діагностика") or {}).get("шари_без_довжини") for x in зв if x.get("правило") == "K-SIL-02")
        Z["K-SIL-02 «утримано» з названим входом (без довжини)"] += any(
            x.get("правило") == "K-SIL-02" and о["id"] in (x.get("речі") or []) for x in відп.get("утримано") or [])
for k, v in Z.items(): print("%-40s %d" % (k, v))
print("сцен, де K-SIL-02 виходить:", len(сцени), {k: len(v) for k, v in сцени.items()})
