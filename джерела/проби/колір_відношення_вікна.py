# -*- coding: utf-8 -*-
"""КОЛІР-ВІДНОШЕННЯ (рядок 3420): кодування відношень вікнами (`колір_відношення`) проти твердих меж (Р2а: той самий сектор ±15° і
сусідній; K-PAL-05; `RELATIONS`) на пулі руки 1 — 4 сцени стенда, пари речей різних слотів. (1) Акценти (C* ≥ 12): кодування без
розмиття (σ = 0) мусить дати ті самі вердикти, що `колір_річ.відношення` (класи тону й `value_step`); по кожному класу тону — ДО
(тверда межа) → ПІСЛЯ: ядро (сила ≥ 0.95), край (0.05–0.95), поза (≤ 0.05). (2) Нейтраль чи майже чорна річ (C* < 12 або L* < 20) ×
будь-яка, вибірка 3 000 на сцену: «same_hue» з певністю тону. (3) Приклади на краю вікна «same_hue».
Запуск із джерела/: python3 проби/колір_відношення_вікна.py"""
import json, random, sys, collections as K; sys.path.insert(0, ".")
import bridge as B, colorspace as cs, стенд_знімок as СЗ, колір_річ as КР, колір_відношення as КВ
вх0 = json.load(open("стенд_вх.json", encoding="utf-8")); Л, П, рп = K.Counter(), [], random.Random(3)
def тверде(f):                                      # кодування без розмиття = межі колір_річ (Р2а, K-PAL-05, RELATIONS)
    б = (КВ.СІГМА_МЕЖІ, КВ.СІГМА_СВІТЛОТИ, КВ.ВІКНА_ΔH); КВ.СІГМА_МЕЖІ = КВ.СІГМА_СВІТЛОТИ = 0.0; КВ.ВІКНА_ΔH = {}
    try: return f()
    finally: КВ.СІГМА_МЕЖІ, КВ.СІГМА_СВІТЛОТИ, КВ.ВІКНА_ΔH = б
кошик = lambda с: "ядро" if с[0] >= 0.95 else "поза" if с[1] <= 0.05 else "край"
КЛ = ("same_hue", "adjacent", "near_hue", "analogous", "square", "triadic", "split", "complementary")
опис = lambda x: "%-30s %s" % ((x.get("назва") or "")[:30], cs.hex_з_lab(x["lab"]) if not КР.не_вимір(x) else "~" + (x.get("колір_ім") or "?"))
for назва in ("офіс·18°C", "дощ·ресторан·вечір", "весілля·гість", "спека·парк"):
    к = json.loads(B.виклик("запити", json.dumps(dict(вх0, сценарій=dict(СЗ.СЦЕНАРІЇ[назва]), випадок=назва), ensure_ascii=False)))["кандидати"]
    зі = {r["id"]: r for r in B.каталог_останнього_пакета()}
    рр = [(с, зі[r["id"]]) for с, xs in к.items() for r in xs if зі.get(r["id"]) and КР.межі_кольору(зі[r["id"]])]
    ак = [(с, x) for с, x in рр if КР.межі_кольору(x)[2] >= 12]
    for i, (с1, a) in enumerate(ак):
        for с2, b in ак[i + 1:]:
            if с1 == с2: continue
            Л["(1) пар акцентів"] += 1
            Л["(1) тверде ≠ колір_річ.відношення"] += any(тверде(lambda: КВ.вердикт(КВ.сила(a, b, кл, певність=False))) != КР.відношення(a, b, кл) for кл in КЛ[:3] + КЛ[5:] + ("value_step",))
            for кл in КЛ:
                с = КВ.сила(a, b, кл, певність=False)
                Л["(1) %-13s ДО %-8s → %s" % (кл, тверде(lambda: КВ.вердикт(КВ.сила(a, b, кл, певність=False))), кошик(с))] += 1
                if кл == "same_hue" and 0.2 < с[0] == с[1] < 0.8 and рп.random() < 0.004:
                    П.append("  %s × %s Δколо %5.1f → сила %.2f" % (опис(a), опис(b), КР.кут_на_колі(cs.lch(a["lab"])[2], cs.lch(b["lab"])[2]), с[0]))
    нт = [(с, x) for с, x in рр if КР.межі_кольору(x)[2] < 12 or КР.межі_кольору(x)[1] < 20]
    for (с1, a), (с2, b) in ((рп.choice(нт), рп.choice(рр)) for _ in range(3000)):
        if с1 == с2: continue
        до = тверде(lambda: КВ.вердикт(КВ.сила(a, b, "same_hue", певність=False)))
        Л["(2) same_hue ДО %-8s → з певністю тону: %s" % (до, кошик(КВ.сила(a, b, "same_hue")))] += 1
        Л["(2) achromatic ≥ 0.5"] += КВ.сила(a, b, "achromatic")[0] >= 0.5
for к_, v in sorted(Л.items()): print("  %-58s %6d" % (к_, v))
print("(3) приклади на краю вікна «same_hue» (сила 0.2–0.8):\n" + "\n".join(П[:10]))
