"""Рядок 2141: «хочу на роботу образ із моєю блузою з фото і костюмом-двійкою» — чи доходить її блуза до П-1.
Записані відповіді моделі розмови: ДО — живий С6 (MamayLM, без own_items), ПІСЛЯ — та сама репліка з own_items, як
просить новий рядок промпта. Друкує рядок own_items промпта, own_items ходу і закріплені «твої» речі кадру П-1.
Запуск: cd джерела && python3 проби/власні_речі_2141.py"""
import json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import мовний_шар as М, річ_з_фото as Р
РЯДОК = [р for р in М._коди_розмови() if р.startswith("- own_items")][0]
print("промпт ходу:", РЯДОК[:230])
ЇЇ = "хочу на роботу образ із моєю блузою з фото і костюмом-двійкою"
ДО = {"update": {"occasion": {"quote": "на роботу", "value": "work"}, "event": "робота"}, "need": "build",
      "text": "Записала: образ на роботу."}
ПІСЛЯ = dict(ДО, update=dict(ДО["update"], own_items=[
    {"quote": "із моєю блузою з фото", "name": "блуза з фото", "status": "has", "slot": "top"}]))
В = json.dumps({"items": [   # П-1 живого С6: модель зору назвала «mine» три речі кадру
    {"photo": "ф1", "name": "yellow shirt", "slot": "top", "color": "yellow", "owner": "mine",
     "frame": {"left": 0, "top": 160, "right": 698, "bottom": 643}},
    {"photo": "ф1", "name": "yellow pants", "slot": "bottom", "color": "yellow", "owner": "mine",
     "frame": {"left": 328, "top": 537, "right": 640, "bottom": 950}}]})
for підпис, відп in (("ДО (живий С6)", ДО), ("ПІСЛЯ (з own_items)", ПІСЛЯ)):
    вн = М.прийняти_розмову(json.dumps(відп, ensure_ascii=False))["внутрішня"]
    власні = [р for р in вн.get("own_items") or [] if М.цитата_тримає(р.get("quote"), ЇЇ)]   # сторож цитати шару
    речі = Р.речі_з_відповіді_фото(В, [{"ід": "ф1", "ширина": 600, "висота": 900}], власні=власні)["речі_з_фото"]
    print("%s: own_items %d, клаузи шару %s; П-1 закріплено «твоїми» %d: %s" % (
        підпис, len(власні), [к["назва"] + "/" + к["слот"] for к in М._її_речі(власні)],
        sum(1 for р in речі if р["закріплена"] and р["чия"] == "моя"),
        "; ".join("%s чия=%s закр=%s" % (р["назва"], р["чия"], р["закріплена"]) for р in речі)))
