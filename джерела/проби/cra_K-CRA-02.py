"""K-CRA-02 (рівно один фокус) на живому шляху: `python3 проби/cra_K-CRA-02.py`.

ЧОМУ БУВ «ЛИШЕ СЛІД»: правило згадувалось у двох місцях і не мало жодного —
`brief.дод` писав `trace.запис` без знахідки, а `колір_образу` цитував K-CRA-02 у
ТЕКСТІ чужої знахідки (K-COL-02). Пункт 2 чекліста надлишку через це стояв
«пройдено» на будь-якому образі: провал ставить лише знахідка.
ЩО ПОКАЗУЄ ПРОБА: образ із трьома джерелами інтересу дає рядок K-CRA-02 у вердикті
І перекидає пункт чекліста з «пройдено» в «провал» — обидва канали разом."""
import sys, pathlib, json
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B

вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["гілка"] = 0
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
пул = json.loads(r["руки"]["1"])["пул"]
взяті, речі = set(), []
for слот in ("верх", "низ", "взуття", "шарф", "прикраси"):
    for к in (пул.get(слот) or []):
        if к["н"] not in взяті:            # одна річ не може стояти у двох слотах
            взяті.add(к["н"]); речі.append(к["н"]); break
print("образ:", речі)
вд = json.loads(B.виклик("від_моделі", json.dumps(dict(
    вх, текст_моделі=json.dumps({"версія": "1", "образи": [
        {"ід": "о1", "речі": речі}]}, ensure_ascii=False)), ensure_ascii=False)))
о = ((вд.get("вердикт") or {}).get("образи") or [{}])[0]
з = next((z for z in (о.get("знахідки") or []) if z["правило"] == "K-CRA-02"), None)
print("K-CRA-02 у вердикті:", "НЕМА" if not з else
      "%s %.2f · %s" % (з["сила"], з["сила_нп"], з["суть"][:60]))
print("  речі рядка:", (з or {}).get("речі"), "· регістр", (з or {}).get("регістр"))
провал = ((о.get("чекліст") or {}).get("надлишок") or {}).get("провал") or []
print("пункт 2 чекліста надлишку:",
      "провал" if "рівно один фокус" in провал else "НЕ провал (%s)" % провал)
print("стеля сили: корпус дає K-CRA-02 `strong`, константа `focus_area` — T3,")
print("  тож `_обмежити_тіром` знижує до «%s»: сила ≤ верифікація" % (з or {}).get("сила"))
assert з and "рівно один фокус" in провал, (з, провал)
