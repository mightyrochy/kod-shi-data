"""Пул лише з інтервалів доходить до членства палітри й переважування заміни."""
import sys
from unittest.mock import patch
sys.path.insert(0, ".")
import оцінка_образу as О, річ_з_фото as Р, verify as В, фід_збагачення as З


import колір_річ as _КОЛІР
def головна():
    """Ізолювати пошук крамниці; членство палітри й генератор виконуються штатно."""
    р = dict(id="синій-інтервал", слот="верх", тип="блуза", колір_тип="інтервал", lab=None,
             колір_не_вимір=З.не_вимір_кольору(В.ЛЕКСИКОН["синій"], "синій", "shop_word"))
    палітра = dict(вікна=dict(L=(0, 100), C=(0, 200), сім_ї=dict(усі=[(0, 359.99)])))
    assert Р.членство_вікна(р, палітра)[0] == "так"
    стара = dict(ід="її-верх", слот="верх")
    for кандидат, очікувано in ((р, 1), (dict(р, колір_тип="невідомо"), 0)):
        with patch.object(О, "_цілі", return_value=[стара["ід"]]), \
             patch.object(О._РФ, "запис_каталогу", return_value=dict(id=стара["ід"], слот="верх")), \
             patch.object(О, "_крамниця", return_value=({"верх": [кандидат]}, "проба", True, {})), \
             patch.object(О, "_ваги_образу", return_value=dict(сума_сил=0)), \
             patch.object(О._СЧ, "відсутнє_на_фото", side_effect=lambda о, *а: (о, [])), \
             patch.object(О, "_покажчики_вітрини_кроками", return_value=iter(())), \
             patch.object(О, "вітрина", return_value={}), \
             patch.object(О._РФ, "членство_вікна", wraps=Р.членство_вікна) as членство:
            г = О.зміни_кроками({}, {}, {}, {}, [стара], [стара["ід"]], [], dict(сума_сил=1), палітра)
            try:
                while True: next(г)
            except StopIteration as кінець:
                зміни, звіт = кінець.value
        print(_КОЛІР.явний_тип_кольору(кандидат), "викликів членства:", членство.call_count,
              "спроб:", len(звіт["спроби"]), "замін:", len(зміни))
        assert членство.call_count == len(звіт["спроби"]) == len(зміни) == очікувано


if __name__ == "__main__":
    головна()
