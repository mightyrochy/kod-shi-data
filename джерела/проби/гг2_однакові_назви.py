"""ГГ-2 (08.10): дві речі з ОДНАКОВОЮ назвою — кожна у своєму слоті; нічия вузлів — не за абеткою.
Синтетичний образ без каталогу й моделі: «Футболка базова» і верхом (id «a»), і верхнім шаром (id «b»).
До ГГ-2 `graph.граф` вішав ребро про будь-яку з них на слот ОСТАННЬОЇ (словник назва → слот) і знахідка про
верх тиснула на верхній шар. Після — знахідка з `учасники.речі` (id) лягає на свій слот, а знахідка лише з
назвою — на обидва (якої з двох вона стосується, назва не каже). Нічия: два слоти з рівною напругою й числом
ребер — до ГГ-2 вузол напруги давала абетка («верхній_шар» < «низ»), після — власна напруга, далі порядок `СЛОТИ`."""
import os, sys
Д = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, Д); os.chdir(Д)
import graph as ГР
речі = [dict(id="a", слот="верх", назва="Футболка базова"), dict(id="b", слот="верхній_шар", назва="Футболка базова"),
        dict(id="c", слот="низ", назва="Штани"), dict(id="d", слот="взуття", назва="Лофери")]
def зн(правило, речі_, **уч):
    return dict(правило=правило, сила_нп=0.5, суть="біля обличчя, на плечі", чому="", речі=речі_,
                **({"учасники": уч} if уч else {}))
г = ГР.граф([зн("A-верх", ["Футболка базова"], речі=["a"]), зн("B-шар", ["Футболка базова"], речі=["b"]),
             зн("C-назва", ["Футболка базова"])], речі)
for р in г["ребра"]:
    print("%-8s вузли %s" % (р["правило"], р["вузли"]))
# нічия: по ребру на «низ» і «верхній_шар» з тією самою силою
г2 = ГР.граф([dict(правило="N1", сила_нп=0.4, суть="", чому="", речі=["c"]),
              dict(правило="N2", сила_нп=0.4, суть="", чому="", речі=["b"])], речі)
print("нічия «низ» / «верхній_шар» (0.4, 1 ребро кожен) → вузол напруги:", ГР.вузол_напруги(г2)["вузол"])
