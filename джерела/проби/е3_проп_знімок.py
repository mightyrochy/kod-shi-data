"""Знімок ваги кожної знахідки розбір_відповідей / суд_інтерес; аргументи: корінь дерева (ДО чи ПІСЛЯ), вихід .json.gz."""
import collections, gzip, json, pathlib, sys


def main():
    """Записати сиру й обмежену вагу, силу, `блокує` й відбиток на тих самих входах; набори — з дерева цієї проби."""
    дерево = pathlib.Path(sys.argv[1]).resolve() / 'джерела'
    sys.path[:0] = [str(дерево), str(pathlib.Path(__file__).resolve().parent)]
    import розбір_відповідей as Р, суд_інтерес as І, outfit as О
    from реєстр_сила import обмежити_вагу
    from е3_проп_набори import набори
    for м in (Р, І):
        assert pathlib.Path(м.__file__).resolve().parent == дерево, м.__file__
    def заглушка(E, **kw):
        """Метрики образу: база має 2 джерела інтересу, видалення будь-якої речі лишає 0 (гілка K-INT-04)."""
        повний = len(E) >= заглушка.розмір
        return dict(інтерес=2 if повний else 0, знахідок=0, вага_знахідок=0.0)

    def крок_заглушка(образ):
        заглушка.розмір = len(О.елементи(образ, стан='надворі'))
        справжня, І.метрики_образу = І.метрики_образу, заглушка
        try:
            return І.крок_редагування(О.елементи(образ, стан='надворі'), речі=образ, стан='надворі', intent='повсякдення')[1]
        finally:
            І.метрики_образу = справжня

    функції = dict(крок_заглушка=крок_заглушка,
                   застосувати_свідомі=lambda *a: Р.застосувати_свідомі(*a)[0],
                   крок_редагування=lambda образ: І.крок_редагування(О.елементи(образ, стан='надворі'), речі=образ,
                                                                     стан='надворі')[1])
    вих, підсумок = [], collections.Counter()
    for назва, функція, args, kwargs in набори():
        for з in функції[функція](*args, **kwargs):
            if функція != 'застосувати_свідомі' and з['правило'] not in ('K-INT-04', 'K-CRA-04'):
                continue
            еф = обмежити_вагу([dict(з)])[0]
            вих.append([назва, функція, з['правило'], з.get('суть'), з.get('речі'), з.get('сила'), з.get('блокує'),
                        з.get('сила_нп'), еф.get('сила_нп'), bool(еф.get('під_підлогою')), з.get('сила_нп_джерело'),
                        з.get('свідомий')])
            підсумок[з['правило'], з.get('сила')] += 1
    with gzip.open(sys.argv[2], 'wt', encoding='utf-8') as ф:
        json.dump(вих, ф, ensure_ascii=False)
    print('знахідок', len(вих), sorted(підсумок.items()))


if __name__ == '__main__':
    main()
