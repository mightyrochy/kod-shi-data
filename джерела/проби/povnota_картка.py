# -*- coding: utf-8 -*-
"""ПРОБА: образ на 3 речі (сукня+взуття+прикраса) доходить до картки мовчки.

Синтетична модель віддає 10 таких образів реальними номерами пулу. Проба друкує
слоти вітрини ремонту (чи є там «сумка»), рішення коду про повноту й те, що дає
крок вибору — до правки й після, тими самими числами.
ДО правки: вітрина без сумки, `вибір.ід` порожній, на картку йшли 3 речі.
ПІСЛЯ: у вітрині сумка, модель бере її звідти — `вибір.ід` на 4 речі; при відмові
`повнота.рядок` каже жінці, чого бракує."""
import json, os, sys
_ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _ТУТ); os.chdir(_ТУТ)
import bridge as B

ПРИКРАСИ = ("сережки", "кольє", "намисто", "браслет", "каблучка", "брошка", "прикраси")
вх = dict(json.load(open("стенд_вх.json")), каталог="каталог_brief.xml",
          сценарій=dict(нагода="побачення", місце="ресторан", година=19, темп_c=20),
          випадок="побачення, ресторан, 19:00, 20 °C")
міст = lambda **д: json.loads(B.виклик("від_моделі", json.dumps(dict(вх, **д), ensure_ascii=False)))
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
пул = json.loads(з["руки"]["1"])["пул"]
_н = lambda с, i: (пул.get(с) or [])[i % len(пул[с])]["н"]
_ядро = "сукня" if пул.get("сукня") else "верх"
_прик = next((с for с in ПРИКРАСИ if пул.get(с)), None)
print("пул: сукня %d, взуття %d, сумка %d, прикраси(%s) %d"
      % (len(пул.get("сукня") or []), len(пул.get("взуття") or []),
         len(пул.get("сумка") or []), _прик, len(пул.get(_прик) or [])))
образи = [dict(ід="о%d" % i, підпис="проба %d" % i,
               речі=[_н(_ядро, i), _н("взуття", i)] + ([_н(_прик, i)] if _прик else []))
          for i in range(1, 11)]
відп = json.dumps(dict(версія="1", образи=образи), ensure_ascii=False)
в1 = міст(текст_моделі=відп)
в2 = міст(текст_моделі=відп, ітерація=2, попередній_вердикт=в1.get("вердикт"))
вітрина = (в2.get("вердикт") or {}).get("вітрина") or {}
о1 = ((в2.get("вердикт") or {}).get("образи") or [{}])[0]
print("образів %d, блокери о1: %s" % (len((в2.get("вердикт") or {}).get("образи") or []),
      [b.get("код") for b in ((о1.get("структура") or {}).get("блокери") or [])]))
print("вітрина слоти: %s | сумка у вітрині: %s" % (sorted(вітрина), "сумка" in вітрина))
в3 = міст(ітерація=2, відповідь="ВИБІР_V1", вибір_над=в2.get("вибір_над"),
          текст_моделі=json.dumps(dict(версія="1", обрано="о1", чому="проба"), ensure_ascii=False))
print("вибір.ід %d речей | перевірено %s" % (len((в3.get("вибір") or {}).get("ід") or []),
                                             в3.get("перевірено")))
пвн = в2.get("повнота") or {}
print("НА КАРТКУ (рішення коду): речей %d, повний %s, рядок: %s"
      % (len(пвн.get("ід") or []), пвн.get("повний"), str(пвн.get("рядок"))[:90]))
print("промпт_повноти: %s символів" % len(в2.get("промпт_повноти") or ""))
# РЕМОНТ ПОВНОТИ: модель бере сумку з вітрини й лишає решту образу
сумка = (вітрина.get("сумка") or [{}])[0].get("н")
полагоджений = json.dumps(dict(версія="1", образи=[dict(
    ід="о1", підпис="доповнено з вітрини", речі=образи[0]["речі"] + ([сумка] if сумка else []))]),
    ensure_ascii=False)
в4 = міст(текст_моделі=полагоджений, ітерація=2, попередній_вердикт=в2.get("вердикт"))
о4 = ((в4.get("вердикт") or {}).get("образи") or [{}])[0]
print("ПІСЛЯ РЕМОНТУ ПОВНОТИ: речей %d, блокери структури %s, на картку %d речей"
      % (len(о4.get("речі") or []),
         [b.get("код") for b in ((о4.get("структура") or {}).get("блокери") or [])],
         len((в4.get("повнота") or {}).get("ід") or [])))
