# -*- coding: utf-8 -*-
"""ПРОБА: образ на 3 речі (сукня+взуття+прикраса) доходить до картки мовчки.

Синтетична модель віддає 10 таких образів реальними номерами пулу; проба
друкує, які слоти має вітрина ремонту (чи є там «сумка»), і що дає крок вибору.
До правки: вітрина без сумки, `вибір.ід` порожній, а на картку йдуть 3 речі
вердикта ітерації 2 — рівно те, що бачила власниця."""
import json, os, sys
_ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _ТУТ); os.chdir(_ТУТ)
import bridge as B

ПРИКРАСИ = ("сережки", "кольє", "намисто", "браслет", "каблучка", "брошка", "прикраси")
вх = dict(json.load(open("стенд_вх.json")), каталог="каталог_brief.xml",
          сценарій=dict(нагода="побачення", місце="ресторан", година=19, темп_c=20),
          випадок="побачення, ресторан, 19:00, 20 °C")
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
пул = json.loads(з["руки"]["1"])["пул"]
_н = lambda с, i: (пул.get(с) or [])[i % len(пул[с])]["н"]
_ядро = "сукня" if пул.get("сукня") else "верх"
_прик = next((с for с in ПРИКРАСИ if пул.get(с)), None)
print("пул: сукня %d, взуття %d, сумка %d, прикраси(%s) %d"
      % (len(пул.get("сукня") or []), len(пул.get("взуття") or []),
         len(пул.get("сумка") or []), _прик, len(пул.get(_прик) or [])))
образи = [dict(ід="о%d" % i, підпис="проба %d" % i,
               речі=[_н(_ядро, i), _н("взуття", i)] + ([_н(_прик, i)] if _прик else []))
          for i in range(1, 11)]
відп = json.dumps(dict(версія="1", образи=образи), ensure_ascii=False)
в1 = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=відп), ensure_ascii=False)))
в2 = json.loads(B.виклик("від_моделі", json.dumps(
    dict(вх, текст_моделі=відп, ітерація=2, попередній_вердикт=в1.get("вердикт")), ensure_ascii=False)))
вітрина = (в2.get("вердикт") or {}).get("вітрина") or {}
о1 = ((в2.get("вердикт") or {}).get("образи") or [{}])[0]
print("образів %d, блокери о1: %s" % (len((в2.get("вердикт") or {}).get("образи") or []),
      [b.get("код") for b in ((о1.get("структура") or {}).get("блокери") or [])]))
print("вітрина слоти: %s | сумка у вітрині: %s"
      % (sorted(вітрина), "сумка" in вітрина))
в3 = json.loads(B.виклик("від_моделі", json.dumps(
    dict(вх, ітерація=2, відповідь="ВИБІР_V1", вибір_над=в2.get("вибір_над"),
         текст_моделі=json.dumps(dict(версія="1", обрано="о1", чому="проба"), ensure_ascii=False)),
    ensure_ascii=False)))
print("вибір.ід %s | перевірено %s | чому: %s"
      % ((в3.get("вибір") or {}).get("ід"), в3.get("перевірено"), str(в3.get("чому"))[:90]))
print("НА КАРТКУ (як робить показ, коли вибору нема) — речей вердикта ітерації 2: %d"
      % len(в2.get("речі") or []))
