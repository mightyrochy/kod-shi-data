# -*- coding: utf-8 -*-
"""ФІГ-1, рядок 310 (Ф-6, П8): мета «вище» перемикає лінію талії в K-FIT-04. Друкує
вердикти K-FIT-04 на кожному низі каталогу (одне тіло, заправлений верх) ДО — так, як
код судив за будь-якої мети (= мета «лестити»), — і ПІСЛЯ на меті «вище».
Запуск із теки `джерела`: `python3 проби/фіг1_талія_вище.py`."""
import os, sys, collections
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as ФК, fit as ПС

кат = ФК._прочитати_каталог(feed.каталог_на_диску(), ліміт_фото=0)["каталог"]
т = ПС.тіло(158, {"плечі": 92, "груди": 90, "талія": 72, "стегна": 100})
H = т["висоти"]
низи = [r for r in кат if r.get("слот") in ("низ", "комплект")]
верх = dict(id="верх", слот="верх", верх_см=H["плечі"], низ_см=H["стегна"], заправлено=True)
підсумок = {м: collections.Counter() for м in ("лестити", "вище")}
приклад = {}
for r in низи:
    річ = dict(id=r["id"], слот=r["слот"], верх_см=H["талія"], низ_см=H["щиколотка"],
               **({"посадка": r["посадка"]} if r.get("посадка") else {}))
    for м in підсумок:
        зн = [з for з in ПС.посадка_пояса(т, [верх, річ], м) if з["правило"] == "K-FIT-04"]
        for з in зн:
            підсумок[м][(r.get("посадка") or "—", з["сила"], з["регістр"])] += 1
            приклад.setdefault((м, з["сила"]), з["суть"])
        if not зн:
            підсумок[м][(r.get("посадка") or "—", "мовчить", "")] += 1
print("низів каталогу: %d; посадка в картці: %s" % (
    len(низи), dict(collections.Counter(r.get("посадка") or "—" for r in низи))))
for м, назва in (("лестити", "ДО (будь-яка мета)"), ("вище", "ПІСЛЯ, мета «вище»")):
    print("  %s:" % назва)
    for (пос, сила, рег), n in sorted(підсумок[м].items()):
        print("      посадка %-8s → K-FIT-04 %-9s %-8s × %d" % (пос, сила, рег, n))
for (м, сила), суть in sorted(приклад.items()):
    print("  приклад [%s · %s]: %s" % (м, сила, суть[:110]))
