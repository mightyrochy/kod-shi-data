"""Міряє залишок і повтор JSON-крамниці після помилки API, стелі та межі пагінації."""
import sys, tempfile
from каталог_зависла_крамниця_json_проба import прогін, порція, РІЧ

def main():
    """Порівнює два запуски зі спільним журналом і пропуск лише після підтвердженого кінця."""
    помилок = 0
    for сім in ("woo", "shopify"):
        for назва, відповіді in (
            ("HTML 502", [(502, "<html>Bad Gateway</html>")] * 3),
            ("JSON 502", [(502, "[]")] * 3),
            ("HTTP 403", [(403, "[]")] * 3),
            ("об’єкт помилки", [(200, '{"code":"error"}')] * 3),
            ("null", [(200, "null")] * 3),
            ("хибні речі", [порція(сім, [None])] * 3),
            ("друга сторінка", [порція(сім, [РІЧ]), (502, "<html>Bad Gateway</html>")]),
            ("стеля", [порція(сім, [РІЧ])]),
            ("межа сторінок", [порція(сім, [РІЧ])] * 120),
        ):
            with tempfile.TemporaryDirectory(prefix="обхід-json-повтор-") as ж:
                до, _ = прогін(ж, сім, відповіді, стеля=1 if назва == "стеля" else 300)
                після, запитів = прогін(ж, сім, [порція(сім, [РІЧ]), порція(сім, [])])
                _, зайвих = прогін(ж, сім, [])
                добре = int(до["лишилось"]) > 0 and запитів == 2 and після["лишилось"] == "0" and після["готово"] == "1" and зайвих == 0
                print(f"{сім}/{назва}: залишок={до['лишилось']}, повтор={запитів}/2, готово={після['готово']}, кінець={після['лишилось']}, зайвих={зайвих}; {'так' if добре else 'ПОМИЛКА'}")
                помилок += not добре
        with tempfile.TemporaryDirectory(prefix="обхід-json-порожня-") as ж:
            стан, запитів = прогін(ж, сім, [порція(сім, [])])
            _, зайвих = прогін(ж, сім, [])
            добре = стан["лишилось"] == "0" and запитів == 1 and зайвих == 0
            print(f"{сім}/порожній каталог: кінець={стан['лишилось']}, зайвих={зайвих}; {'так' if добре else 'ПОМИЛКА'}")
            помилок += not добре
    print(f"JSON-повтор: помилок {помилок}/20")
    return int(bool(помилок))

if __name__ == "__main__":
    sys.exit(main())
