"""КОЛО-РОЛІ-3 (наряд 2.1-В, рядки 8470, 8530): чи хибу насичених рожевих лікує міра відстані тону, що враховує хрому.
Пари аркуша 2.1-Б (гілка `claude/kolo-roli-2-1-b-arkush`, `аудит/перевірка/2.1-Б/аркуш_тон.json`): річ (L*, C*, h*) і
край дуги на тих самих L*, C*; очима «так» — #13 #25 #30 (рожеве в рожевій дузі), «ні» — #20 #40 #28 (рожеве в червоній і
коралово-червоній дузі), #2 #4 #9 (червоне/помаранчеве проти бурштину). Друкує Δh, ΔH* і ΔE00 (його S_H = 1 + 0.015·C̄·T(h)
— поправка і на хрому, і на тон): коли «так» і «ні» однієї ділянки кола стоять на тій самій відстані, симетрична міра від
краю їх не розведе — межа в них категорійна (з якого боку межі рожеве | червоне річ і центр дуги), а не відстань.
Запуск із джерела/: python3 проби/коло_ролі_рожеві_8470.py"""
import math, sys; sys.path.insert(0, ".")
from колір_простір_перетворення import de00
ПАРИ = (("#13 так", 46.8, 43.5, 2.9, 354.0), ("#25 так", 50.8, 69.1, 12.5, 6.0), ("#30 так", 54.1, 72.1, 10.6, 3.0),
        ("#20 ні", 42.9, 61.9, 7.9, 15.0), ("#40 ні", 42.4, 53.4, 8.1, 15.0), ("#28 ні", 64.7, 57.4, 1.8, 10.0),
        ("#2 ні", 55.6, 92.4, 45.2, 40.0), ("#4 ні", 42.1, 74.7, 31.1, 36.0), ("#9 ні", 52.9, 75.4, 31.3, 39.0))
lab = lambda L, C, h: (L, C * math.cos(math.radians(h)), C * math.sin(math.radians(h)))
рожеві = {"так": [], "ні": []}
for ім, L, C, h, край in ПАРИ:
    dh = min(abs(h - край) % 360, 360 - abs(h - край) % 360)
    е = de00(lab(L, C, h), lab(L, C, край))
    if h < 20 or h > 340:
        рожеві[ім.split()[1]].append(е)
    print("%-7s L%3.0f C%3.0f h%5.1f край %5.1f  Δh %4.1f°  ΔH* %4.1f  ΔE00 %.2f" % (ім, L, C, h, край, dh, 2 * C * math.sin(math.radians(dh) / 2), е))
print("рожеві h* 340–20: ΔE00 «так» %.2f–%.2f, «ні» %.2f–%.2f — %s" % (min(рожеві["так"]), max(рожеві["так"]), min(рожеві["ні"]),
      max(рожеві["ні"]), "перетинаються: міра від краю не розводить" if min(рожеві["так"]) <= max(рожеві["ні"]) else "розведені"))
