"""K-COL-02 (бюджет хроми) — від «нікуди» до рядка у вердикті.

Корпус (тема-4:302): «≤1–2 високонасичених елементи на образ, РАХУЮЧИ волосся
(фарбоване — постійний приобличчевий акцент) і оправу. FORCE: strong, регістр
`репліка`». Емітент `колір_образу.бюджет_хроми` написаний правильно й стоїть за
гейтом площі в `суд_образу.review`; на `каталог_повний.xml` (10 770 офферів)
речей із походженням площі — 0, тож гейт закритий на 100 % образів і правило не
казало нічого жодного разу.
ПІСЛЯ: `pipeline.бюджет_і_відлуння` рахує ГУЧНІ елементи зі слота й виміряного
кольору — лічбі площа не потрібна. Запуск із теки `джерела`:
`python3 проби/col_K-COL-02.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import реєстр_правил as РЕЄСТР

гучно = РЕЄСТР.C["hi_C"]
вх, r, кат, спец = ПВ.стенд(гілка=0)
гучний = lambda L, C, h, _: C >= гучно
взяті = [(с, ПВ.з_каталогу(кат, с, гучний)) for с in ("верх", "низ", "взуття", "сумка")]
взяті = [(с, x) for с, x in взяті if x]
print("гучних речей (C* ≥ %.0f) у пакеті каталогу: %d із %d із виміряним кольором"
      % (гучно, sum(1 for c in кат.values() if c.get("lab") and ПВ.cs.lch(c["lab"])[1] >= гучно),
         sum(1 for c in кат.values() if c.get("lab"))))
for с, x in взяті:
    print("   %-8s «%s» C*%.0f" % (с, x["назва"][:38], ПВ.lch(кат, x["id"])[1]))
зн, _ = ПВ.знахідки(вх, [x["id"] for _, x in взяті])
print("ФАКТ · K-COL-02: %s" % ПВ.рядок(зн, "K-COL-02"))
z = next((x for x in зн if x.get("правило") == "K-COL-02"), None)
assert z, "чотири гучні речі в образі не дали K-COL-02"
assert z["сила"] == "strong" and z["сила_нп"] == 0.75, z          # корпусна сила
assert z["регістр"] == "репліка", z        # корпус: «повний штраф, ніколи не вето»
assert len(z["речі"]) == len(взяті) and z["ремонт"], z   # усі гучні названі поіменно
print("       ремонт: %s" % z["ремонт"])
