"""КОЛІР-ПЕРЕКЛАД (рядок 4820): код кольору речі в промпті перекладу проти `color` пакета, ДО/ПІСЛЯ.
ДО — записані промпти «мовний_шар» (рядки «N — назва · colour code: X»), назва шукається в `pool` записаного
пакета образів. ПІСЛЯ — той самий перелік через `_код_кольору_речі` з `код_кольору` каталогу.
Запуск: python3 проби/колір_перекладу_4820.py <тека з VIDPOVIDI>... (записи: гілка claude/zhyvi-25, аудит/живі_25/А)"""
import glob, json, re, sys
sys.path.insert(0, "."); import мовний_шар as М
ТАБ = М._ВМ.ТАБЛИЦЯ["color_name"]
for тека in sys.argv[1:]:
    речі, ду = {}, []
    for ф in glob.glob(тека + "/VIDPOVIDI/*ПАКЕТ*.txt"):
        for р in json.loads(open(ф, encoding="utf-8").read().split("\n")[1]).get("pool", []):
            речі[р["name"]] = (р.get("color"), р.get("hex"))
    for ф in glob.glob(тека + "/VIDPOVIDI/*мовний_шар*.txt"):
        for н, назва, код in re.findall(r"^(\d+) — (.+?) · colour code: (\w+)", open(ф, encoding="utf-8").read(), re.M):
            ду.append((назва, код))
    знайдено = [(к, речі[н]) for н, к in ду if н in речі and речі[н][0] in ТАБ]
    до = sum(к != c for к, (c, _) in знайдено)
    після = sum(М._код_кольору_речі({"код_кольору": c, "hex": h}) != c for _, (c, h) in знайдено)
    без = М._код_кольору_речі({"hex": "#000080"})
    print(f"{тека.split('/')[-1][:24]}: речей з кодом {len(ду)}, зіставлено {len(знайдено)}, код≠color ДО {до}, ПІСЛЯ {після}")
print("без коду каталогу — hex:", без)
