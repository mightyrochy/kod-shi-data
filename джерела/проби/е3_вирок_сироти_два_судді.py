# -*- coding: utf-8 -*-
"""Е3 15492: вирок K-COL-05 «акцент-сирота» двох суддів (`колір_хрома.відлуння`, `суд_від_моделі.бюджет_і_відлуння`)
над тими самими входами — кожна кольорова річ каталогу в акцентному слоті над нейтральною основою, фокус схеми є/нема.
Друкує `розбіжностей: N` (різний факт «знахідка сироти є/нема»). Запуск з `джерела`: `python3 проби/е3_вирок_сироти_два_судді.py [кат.json]`."""
import json, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import colorspace as cs, outfit as O, колір_хрома as ХР, суд_від_моделі as СМ
шлях = sys.argv[1] if len(sys.argv) > 1 else None
if шлях: кат = json.load(open(шлях, encoding="utf-8"))
else:
    import feed as Ф
    кат = Ф.прогін(Ф.каталог_на_диску("каталог_повний.xml"), [], ліміт_фото=0, кеш="стенд_кеш_кольорів.json")["каталог"]
def річ(x, слот): return dict(id=x["id"], слот=слот, hex=x.get("колір_hex_фото"), lab=tuple(x["lab"]), колір_тип="вимір")
міряні = [x for x in кат if x.get("колір_hex_фото") and x.get("lab") and x.get("колір_тип") == "вимір"]
осн = {с: річ(next(x for x in міряні if x["слот"] == с and cs.lch(tuple(x["lab"]))[1] < 6), с) for с in ("верх", "низ", "взуття")}
площі = {"верх": .3, "низ": .3, "взуття": .03}
акц = [x for x in міряні if x["слот"] in ("сумка", "шарф") and cs.lch(tuple(x["lab"]))[1] >= 20]
сир = lambda зн: any(z.get("правило") == "K-COL-05" and any(a.get("code") == "accent_orphan" for a in z.get("заяви") or []) for z in зн)
всього = розб = 0; приклад = None
for x in акц:
    слот = x["слот"]; речі = [dict(осн[с]) for с in осн] + [річ(x, слот)]
    E = O.елементи(речі)
    for e in E:
        p = площі.get(e["слот"], .02); e["площа"] = p; e["площа_межі"] = (p, p); e["джерело_площі"] = "маски"
    for фокус in (None, [слот]):
        а = сир(ХР.відлуння(E, фокус)); б = сир(СМ.бюджет_і_відлуння(речі, None, {r["id"]: r for r in речі}, фокус))
        всього += 1
        if а != б: розб += 1; приклад = (приклад or []) + [(x["id"], слот, фокус, а, б)]
print("входів: %d · розбіжностей: %d · перша: %s" % (всього, розб, приклад))
