# -*- coding: utf-8 -*-
"""Рядок 113: дві дірки `паспорт_нагоди.паспорт_з_json` на відповідях живої 8b (PR #196).
(а) нагода/місце копією довідника («робота — Робота (…)») — ключ стоїть у значенні, а код звіряв
лише з голим ключем → `нагода=None` і зайве питання жінці. (б) поле, назване моделлю в «невідомо»,
все одно читалось → вигадана мета доїжджала в ранг основ і `чому_мети`. Фіксовані рядки JSON, як їх
повертала qwen3-vl-8b на ноутбуці; живої моделі проба не потребує. Друкує факт, нічого не чинить.
Запуск із теки `джерела`: `python3 проби/pasport_json_113.py`."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import паспорт_нагоди as П

СЛОВА = "Вечеря в ресторані з колегами о восьмій"
ВИПАДКИ = [
    ("1 нагода й місце копією довідника",
     '{"нагода": "робота — Робота (зустріч, презентація, співбесіда)", "місце": "офіс — Офіс"}'),
    ("2 мета названа в «невідомо»", '{"мета": "лестити", "невідомо": ["мета"]}'),
    ("3 мета без «невідомо» (контроль)", '{"мета": "лестити", "невідомо": []}'),
    ("4 прикраси в «невідомо», макіяж ні",
     '{"макіяж": {"рівень": "помітний", "губи": "#b0203a"}, "прикраси": "золото",'
     ' "невідомо": ["прикраси образу"]}'),
    ("5 незнайома нагода (контроль)", '{"нагода": "вечірка з друзями"}'),
]
for назва, сир in ВИПАДКИ:
    п = П.паспорт_з_json(сир, {}, СЛОВА)
    пит = [q for q in п["питання_людині"] if "не знаю" in q]
    print("%-36s нагода=%-9s місце=%-16s мета=%-9s мета_слова=%-4s прикраси=%-9s макіяж=%-8s "
          "питань_коду=%d%s"
          % (назва, п["нагода"], п["місце"], п["мета"], "є" if п.get("мета_слова") else "нема",
             п["прикраси"], (п["макіяж"] or {}).get("рівень"), len(пит),
             (" | %s" % пит[0][:52]) if пит else ""))
print("«невідомо» у паспорті лишається як інформація для порад і питань: %s"
      % П.паспорт_з_json('{"мета": "лестити", "невідомо": ["мета"]}', {}, СЛОВА)["невідомо"])
