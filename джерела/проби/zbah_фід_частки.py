# -*- coding: utf-8 -*-
"""Злиття жнив v2 у фід — які частки каталогу несуть ознаку з ФОТО до і після.

Той самий `feed._прочитати_каталог` (офлайн, `ліміт_фото=0`), що будує базу руки 1,
двічі: зі старим файлом збагачення і з новим. Колір — лише за згоди свідків
(`feed.колір_спір`, ПЕРЕДАЧА §5), тож спори лічаться окремо.
Запуск: `python проби/zbah_фід_частки.py ДО.json.gz ПІСЛЯ.json.gz [каталог.xml]`."""
import sys, gzip, json, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import feed as F

def кат(шлях_зб, фід):
    зб = json.load(gzip.open(шлях_зб, "rt", encoding="utf-8"))
    return {c["id"]: c for c in F._прочитати_каталог(фід, ліміт_фото=0, збагачення=зб)["каталог"]}

фід = sys.argv[3] if len(sys.argv) > 3 else "каталог_повний.xml"
до, після = кат(sys.argv[1], фід), кат(sys.argv[2], фід)
ОЗНАКИ = (("колір", "колір_джерело", "фото"), ("крій", "крій_джерело", "фото"),
          ("довжина", "довжина_джерело", "фото"), ("матеріал", "волокно_джерело", "фото"))
print("речей у каталозі %d (до) / %d (після)" % (len(до), len(після)))
for ім, п, зн in ОЗНАКИ:
    ч = lambda к: 100.0 * sum(1 for c in к.values() if c.get(п) == зн) / (len(к) or 1)
    print("   %-9s з фото %5.1f %% → %5.1f %%" % (ім, ч(до), ч(після)))
змін = sum(1 for і, c in після.items() if і in до and c.get("колір_назва") != до[і].get("колір_назва"))
спір = lambda к: sum(1 for c in к.values() if c.get("колір_спір"))
зб = lambda к: sum(1 for c in к.values() if c.get("збагачення"))
print("ФАКТ · речей зі збагаченням %d → %d; слово кольору змінилось у %d; на слові крамниці "
      "через спір %d → %d" % (зб(до), зб(після), змін, спір(до), спір(після)))
