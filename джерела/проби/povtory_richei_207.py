# -*- coding: utf-8 -*-
"""Скарга «Ір» (24.09): «з 12+ тис речей бере 2–3 і мусолить їх в усіх образах». 3 сценарії × сіди 3,5,7,9 × 2 збори поспіль.
«модель» = бере в слоті речі «за_бажанням» по колу (так велить рядок вимоги), інакше і-ту — як заглушка стенда; 10 образів руки 1.
Друкує: різних речей на слот / найчастіша річ у 10 образах; картка = образ 1 руки (руки 1–2 × 2 збори = 4); повтор між зборами."""
import json, os, sys, collections as C
Д = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, Д); os.chdir(Д)
import bridge as B, feed; feed.каталог_на_диску()
база = json.load(open("стенд_вх.json"))
СЦ = {"собаки": (dict(нагода="щоденне", місце="прогулянка з собаками", година=11, темп_c=14), ["яскравий верх, куртку чи жакет", "світлі джинси", "зручне"]),
      "авто·урок·дощ": (dict(нагода="щоденне", місце="авто та урок", година=10, темп_c=12, опади="дощ"), ["кросівки", "джинси", "оригінальний без зусиль", "яскравий верх", "шарф"]),
      "типовий": (база["сценарій"], [])}
СЛ = ("верх", "низ", "верхній_шар", "взуття", "сумка")
def образи(пул, бажане):
    сп = {с: ([x["id"] for x in пул.get(с) or [] if x.get("за_бажанням") and бажане] or [x["id"] for x in пул.get(с) or []]) for с in СЛ}
    return [{с: рч[i % len(рч)] for с, рч in сп.items() if рч} for i in range(10)]
for назва, (сц, бж) in СЦ.items():
    for бажане in ((True, False) if бж else (False,)):
        різні, топ, карт, між = C.defaultdict(list), C.defaultdict(list), C.defaultdict(list), 0
        for сід in (3, 5, 7, 9):
            вже, картки = set(), []
            for збір in (1, 2):
                d = dict(база, сценарій=сц, випадок=назва, сід=сід * 100 + збір, паспорт=dict(бажання=бж), без_фото=1, вже_були=sorted(вже))
                r = json.loads(B.виклик("запити", json.dumps(d, ensure_ascii=False)))
                for рука, к in (("1", r.get("кандидати") or {}), ("2", r.get("кандидати_донора") or {})):
                    об = образи(к, бажане)
                    for с in (СЛ if рука == "1" else ()):
                        п = C.Counter(о[с] for о in об if с in о)
                        if п: різні[с].append(len(п)); топ[с].append(max(п.values()))
                    між += sum(1 for i in об[0].values() if i in вже)
                    картки.append(об[0])
                вже |= {i for о in картки for i in о.values()}
            for с in СЛ:
                п = C.Counter(о[с] for о in картки if с in о)
                if п: карт[с].append(max(п.values()))
        print("ФАКТ · %-13s %-22s " % (назва, "модель за бажанням" if бажане else "заглушка (і-та річ)")
              + " · ".join("%s різних %s/10 топ %s, у 4 картках топ %s" % (с, min(різні[с]), max(топ[с]), max(карт[с])) for с in СЛ if різні[с])
              + " · річ картки збору 1 знову в картці збору 2: %d" % між)
