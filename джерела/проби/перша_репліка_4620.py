"""ПАСПОРТ-34 (рядки 4620–4622): перші ходи розмови ЖИВІ-20…22 — записані відповіді мовної моделі тим кодом, що в теці
аргументу (типово `.`): `прийняти_розмову` → `паспорт_з_шару`. Друкує бульбашку, повторний запит поради (вада) і поля
паспорта (нагода, місце, подія, рух); наприкінці — чи правило частин дня промпту ходу каже про спорт частини дня.
Кращим: бульбашка — речення з кількох слів (не «Зрозуміла.»); на ході без поради при дозволених темах — повторний
запит `no_invite`; поля replay не міняються (відповідь записана), правило частин дня — про спорт: так.
Запуск: cd джерела && python3 проби/перша_репліка_4620.py [тека джерел іншої збірки]"""
import json, subprocess, sys
sys.path.insert(0, sys.argv[1] if len(sys.argv) > 1 else "."); import мовний_шар as М
git = lambda *а: subprocess.run(["git", "-c", "core.quotepath=false", *а], capture_output=True, text=True).stdout
for ж in ("20", "21", "22"):
    г = "origin/claude/zhyvi-" + ж
    git("fetch", "-q", "origin", "claude/zhyvi-" + ж)
    for ф in git("ls-tree", "-r", "--full-tree", "--name-only", г, "аудит/живі_%s/А" % ж).splitlines():
        if not ф.endswith("_01_мовний_шар_хід_розмови.txt"): continue
        с = git("show", "%s:%s" % (г, ф)); вх = json.loads(с.split("\n", 1)[1].split("\n── ВІДПОВІДЬ")[0])
        р = М.прийняти_розмову(с.split("── ВІДПОВІДЬ", 1)[1].split("──", 1)[1])
        if р.get("причина"): print("Ж%s %s · без відповіді" % (ж, ф.split("/")[3][:2])); continue
        ш = М.паспорт_з_шару(р["внутрішня"], {}, слова_ходу=[вх["her_new_message"]], частини=р["частини"])
        п, рем = ш["паспорт"], ш.get("ремонт_поради") or {}
        print("Ж%s №%s · %s · повтор поради %s · %s" % (ж, ф.split("/")[3][:2], ш.get("текст"), рем.get("вада", "—"),
              " · ".join("%s %s" % (к, п.get(к)) for к in ("нагода", "місце", "подія", "рух"))))
п = json.dumps(json.loads(М.промпт_розмови({"розмова": {"нове": "йога зранку, потім кава з подругою", "історія": []}})),
               ensure_ascii=False)
print("правило частин дня про спорт:", "так" if "first part she names that is not a sport" in п else "ні",
      "· says без слова-згоди:", "так" if "never a lone word" in п else "ні")
