"""Рядок 210: «ви» → «ти» МОДЕЛЛЮ, код лише перевіряє (рішення власника 25.09). Правило «за
закінченням» калічило ТРИЧІ, щоразу ПІСЛЯ виміру «безпечно»: «відкрите»→«відкриш»; «плете» (3 ос.
однини)→«плеш», «десятиліть» (іменник)→«десятили»; «почуватиметеся»→«почуватимеся» замість
«почуватимешся», а «Виділіть» лишалось на «ви» через власний виняток. Тепер код ЗНАХОДИТЬ речення на
«ви», модель переписує ЛИШЕ їх, код ЗВІРЯЄ; не зійшлось — лишається оригінал. Фрази тестувальниці
(gemma-4-12b, qwen3.5-9b); живої моделі тут нема, відповіді підставлено. PYTHONPATH=. python3 проби/na_ty_modelliu_210.py"""
import sys; sys.path.insert(0, ".")
import паспорт_нагоди as П
# Фрази тестувальниці (ліворуч) і те, що на них віддала б модель (праворуч).
ПАРИ = [("Ви почуватиметеся впевнено у цьому образі.", "Ти почуватимешся впевнено у цьому образі."),
        ("Виділіть талію поясом.", "Виділи талію поясом."),
        ("Тримайте сумку в руці.", "Тримай сумку в руці."),
        ("Підніміть комір, щоб подовжити шию.", "Підніми комір, щоб подовжити шию."),
        ("Чи ви обранете класичні брюки?", "Чи ти обереш класичні брюки?"),
        ("Ви усміхаєтеся — і образ працює.", "Ти усміхаєшся — і образ працює."),
        ("Я підібрав для вас спокійний образ.", "Я підібрала для тебе спокійний образ."),
        ("Відкрите плече і золоте кольє лишаються.", "Відкрите плече і золоте кольє лишаються.")]
ТЕКСТ, МОДЕЛЬ_ДОБРЕ = " ".join(о for о, _ in ПАРИ), dict(ПАРИ)
ціль, усіх = П.речення_на_ви(ТЕКСТ), len([р for р in П._НА_ТИ_МЕЖА.split(ТЕКСТ) if р.strip()])
print("речень у тексті %d · детектор бере %d (широкий свідомо: хибна знахідка коштує зайвого"
      " рядка в запиті, а не зіпсованого слова)" % (усіх, len(ціль)))
добрі = [МОДЕЛЬ_ДОБРЕ[р] for _, р in ціль]
т, з = П.на_ти(ТЕКСТ, добрі)
print("МОДЕЛЬ ВІДПОВІЛА ДОБРЕ → узято: %s · «ви» лишилось: %d · звіт %s"
      % (з.get("узято"), len(П._НА_ТИ_ЗАЙМЕННИК.findall(т)), з))
print("   %s" % т)
for мітка, відп in (("загубила назву", [x.replace("золоте кольє", "прикраса") for x in добрі]),
                    ("лишила займенник", [добрі[0].replace("Ти", "Ви")] + добрі[1:]),
                    ("вернула незміненим", [ціль[0][1]] + добрі[1:]),
                    ("скоротила", добрі[:-2]), ("моделі нема", None)):
    т2, з2 = П.на_ти(ТЕКСТ, відп)
    print("%-19s → узято %-5s · текст = оригінал: %-5s · %s"
          % (мітка, (з2 or {}).get("узято"), т2 == ТЕКСТ, (з2 or {}).get("чому") or (з2 or {}).get("шлях")))
# ЧОГО КОД СУДИТИ НЕ МОЖЕ І НЕ ВДАЄ, ЩО МОЖЕ: речення без займенника, де звертання видно
# лише закінченням («Виділіть талію поясом»). Звірка це ПРОПУСТИТЬ — відрізняти наказ від
# прикметника формою слова й означало калічити прозу. Лічиться окремо, іде у звіт власника.
_, з3 = П.на_ти(ТЕКСТ, [добрі[0]] + ["Виділіть талію поясом."] + добрі[2:])
print("дієслово без займенника лишено → узято %s · несуджених речень %s (у звіт власника)"
      % (з3.get("узято"), з3.get("несуджених")))
