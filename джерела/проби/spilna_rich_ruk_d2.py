# -*- coding: utf-8 -*-
"""Д-2 (рядок 62): чи беруть руки 1 і 2 одного прогону ТУ САМУ річ каталогу.

Читає пул, який справді бачить модель (`пакети[рука].пул` — порядок показу), і
тягне з нього річ ТИМ розподілом позицій, який Д-1 (PR #355) зміряв на живому
прогоні власника: перша річ слота 12 %, перша чверть 58 %, третина 68 %, половина
78 %. Друкує частку витягів зі спільною річчю, розмір пулу й час прогону.
Прогін: python3 проби/spilna_rich_ruk_d2.py [каталог]
"""
import sys, os, json, time, random
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import bridge as B, пакет_моделі as ПМ

КАТАЛОГ = (sys.argv[1:] or ["каталог_brief.xml"])[0]
СІДИ = (4242, 5, 9, 13, 17, 21, 33, 51, 77, 101, 404, 909)
СЛОТИ = ("сукня", "верх", "низ", "взуття", "сумка", "пояс", "прикраси")
ПРОБ = 200
база = dict(json.load(open("стенд_вх.json", encoding="utf-8")), намір="conventional", без_фото=1)


def взяти(рч, rnd):
    """Річ, яку бере жива модель: сходи Д-1 над позицією в слоті."""
    n, u = len(рч), rnd.random()
    верх = lambda ч: min(max(1, -(-n // ч)), n)
    for межа, a, b in ((.12, 0, 1), (.58, 1, верх(4)), (.68, верх(4), верх(3)),
                       (.78, верх(3), верх(2)), (1.0, верх(2), n)):
        if u < межа:
            a = min(a, n - 1)
            return рч[rnd.randrange(a, max(b, a + 1))]
    return рч[-1]


def пул_рукою(з, рука, ключ):
    """{слот: [id за порядком показу]} — тим самим номером, що бачить модель."""
    зв = {"#%d·%s" % v: k for k, v in ПМ.номери_речей(з.get(ключ) or {})[0].items()}
    return {с: [зв.get(r.get("н")) for r in рч]
            for с, рч in (((з.get("пакети") or {}).get(рука) or {}).get("пул") or {}).items()}


частки, часи, розмір = [], [], []
for сід in СІДИ:
    t = time.time()
    з = json.loads(B.виклик("запити", json.dumps(
        dict(база, каталог=КАТАЛОГ, сід=сід, пакети=1), ensure_ascii=False)))
    часи.append(time.time() - t)
    if з.get("помилка") or з.get("пул_чому"):
        print("сід %-5s НЕ ЗІБРАЛИСЬ: %s" % (сід, з.get("помилка") or з["пул_чому"])); continue
    п1, п2 = пул_рукою(з, "1", "кандидати"), пул_рукою(з, "2", "кандидати_донора")
    слоти = [с for с in СЛОТИ if п1.get(с) and п2.get(с)]
    rnd = random.Random(сід)
    сп = sum(1 for _ in range(ПРОБ) if {взяти(п1[с], rnd) for с in слоти}
             & {взяти(п2[с], rnd) for с in слоти})
    частки.append(сп / ПРОБ); розмір.append((sum(map(len, п1.values())), sum(map(len, п2.values()))))
    print("сід %-5s слотів %d · витягів зі спільною річчю %3d/%d (%.0f %%) · пул 1/2 %d/%d"
          % (сід, len(слоти), сп, ПРОБ, 100 * сп / ПРОБ, розмір[-1][0], розмір[-1][1]))
print("%s · СПІЛЬНА РІЧ У %.0f %% витягів (%d сідів × %d) · пул 1/2 %.0f/%.0f · прогін %.1f с"
      % (КАТАЛОГ, 100 * sum(частки) / max(1, len(частки)), len(частки), ПРОБ,
         sum(x[0] for x in розмір) / max(1, len(розмір)), sum(x[1] for x in розмір) / max(1, len(розмір)),
         sum(часи) / max(1, len(часи))))
