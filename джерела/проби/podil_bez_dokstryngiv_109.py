# -*- coding: utf-8 -*-
"""Факт до/після рядка 109: докстрінг — перший Expr(Constant(str)) у тілі функції,
тому звичайний ast.dump його бачить, і кожна з 14 проб `поділ_*_ast.py` після
доданого докстрінга падає новою розбіжністю (нова пара в поділ_очікувані.json).
Бере реальну функцію з поділеного модуля (`аксесуари_реєстр.py::_зн`, уже має
докстрінг), будує копію без нього — ast.dump розбіжний; dump_без_докстрінгів
(поділ_спільне.py) на тій самій парі тотожний.
Запуск: cd джерела && python3 проби/podil_bez_dokstryngiv_109.py"""
import ast
import copy
import sys

from поділ_спільне import dump_без_докстрінгів

ФАЙЛ, ІМ_Я = "аксесуари_реєстр.py", "_зн"
текст = open(ФАЙЛ, encoding="utf-8").read()
з_докстрінгом = next(n for n in ast.parse(текст).body
                      if isinstance(n, ast.FunctionDef) and n.name == ІМ_Я)
assert ast.get_docstring(з_докстрінгом) is not None, "тестова функція мусить мати докстрінг"

без_докстрінга = copy.deepcopy(з_докстрінгом)
без_докстрінга.body = без_докстрінга.body[1:]

до_ast, після_ast = ast.dump(без_докстрінга), ast.dump(з_докстрінгом)
до_чист, після_чист = dump_без_докстрінгів(без_докстрінга), dump_без_докстрінгів(з_докстрінгом)

print("%s::%s без докстрінга → з докстрінгом" % (ФАЙЛ, ІМ_Я))
print("  ast.dump до == після:", до_ast == після_ast, "(мало бути False — докстрінг ламає пробу)")
print("  dump_без_докстрінгів до == після:", до_чист == після_чист, "(мало бути True — не ламає)")

ФАКТ = (до_ast != після_ast) and (до_чист == після_чист)
print("ФАКТ:", "докстрінг більше не поломка для проб поділу" if ФАКТ else "ПОМИЛКА")
sys.exit(0 if ФАКТ else 1)
