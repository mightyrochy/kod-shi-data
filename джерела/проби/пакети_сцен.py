# -*- coding: utf-8 -*-
"""Наряд «чисті промпти» (25.09.2026): промпт ПАКЕТ_V1 руки 1 для трьох сцен стенда (типовий, весілля,
«Ір») — файлом `<тека>/ПАКЕТ_V1_<сцена>.txt`, щоб `аудит/проби/модель_проти_моделі.js` слав ТІ САМІ
байти живим моделям (gemma-4-12b, qwen3.5-9b) з main і з гілки. Паспорт сцени проходить справжній
розбір (`паспорт` з `json_моделі` — відповідь заглушки стенда тієї сцени), далі `запити`, як у показі.
Моделі не кличе. Друкує довжину промпта й пул. Запуск: cd джерела && python3 проби/пакети_сцен.py <тека>"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B
тека = sys.argv[1] if len(sys.argv) > 1 else "пакети_сцен"
os.makedirs(тека, exist_ok=True)
міст = lambda ім, **в: json.loads(B.виклик(ім, json.dumps(в, ensure_ascii=False)))
вх0 = dict(json.load(open("стенд_вх.json", encoding="utf-8")), варіантів=10, ремонт_варіантів=5,
           бюджет_символів=120000, без_фото=1)
ВЕТО = lambda **к: dict(dict(типи=[], тканини=[], принти=[], кольори=[], зони=[]), **к)
СЦЕНИ = (
    ("типовий", "робочий день в офісі, дрес-код business casual, без підборів",
     dict(подія="робочий день в офісі", нагода="робота", місце="офіс_корпоративний", формат="приміщення",
          рух="сидіти", дрес_код="business_casual", ошатність=[4, 6], опади="ні", намір="conventional",
          вето=ВЕТО(типи=["підбори"]))),
    ("весілля", "в суботу весілля подруги з пʼятої вечора, ресторан, хочу щось легке",
     dict(подія="весілля подруги", нагода="весілля_гість", місце="святкова_вечеря", година=17,
          тривалість_год=7, ошатність=[7, 9], бажання=["щось легке"], вето=ВЕТО())),
    ("Ір", "для авто та на урок, надворі дощ. Можна яскравий верх — куртку чи жакет, не темного кольору",
     dict(подія="для авто та на урок, надворі дощ", нагода="щоденне", опади="так",
          бажання=["яскравий верх — куртка чи жакет"], вето=ВЕТО(кольори=["темні кольори"], зони=["ноги"]))),
)
for ім, слова, відп in СЦЕНИ:
    п = міст("паспорт", сценарій={}, вимоги=слова, json_моделі=json.dumps(відп, ensure_ascii=False))
    r = міст("запити", **dict(вх0, сценарій={}, вимоги=слова, паспорт=п["паспорт"], випадок=п["випадок"]))
    if r.get("помилка"): print(ім, "помилка:", r["помилка"]); continue
    open(os.path.join(тека, "ПАКЕТ_V1_%s.txt" % ім), "w", encoding="utf-8").write(r["руки"]["1"])
    print("%-8s промпт %6d симв · пул %s речей · випадок «%s»" % (ім, len(r["руки"]["1"]), r.get("пул_речей"), п["випадок"]))
