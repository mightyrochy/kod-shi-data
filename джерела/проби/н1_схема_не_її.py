import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import pipeline as PL, колір_образу as КО, суд_від_моделі as СМ

вх, r, кат, спец = ПВ.стенд(гілка=0, намір="statement")
дуга = ((спец.get("слоти") or {}).get("сукня") or {}).get("дуга_тону")


def поза(L, C, h, зап):
    if PL._нейтральний_тон(h, C, L) or КО.не_вимір(зап):
        return False
    lo, hi = float(дуга[0]), float(дуга[1])
    return not ((lo - 10 <= h <= hi + 10) if lo <= hi else (h >= lo - 10 or h <= hi + 10))


річ = next((dict(x, слот=с) for с in ("сукня", "верх")
            for x in [ПВ.взяти(r, кат, с, поза) or ПВ.з_каталогу(кат, с, поза)] if x), None)
assert річ, "нема речі поза дугою схеми — судити нема чого"
слоти = dict(спец.get("слоти") or {}, _схема=спец.get("схема"))
сцен = {"her": {"вибір_схеми": {"обрала": {"scheme": "her"}}},
        "stylist": {"вибір_схеми": {"обрала": {"scheme": "stylist"}}},
        "не питали": None}
for ім, с in сцен.items():
    зн = СМ.схема_образу([dict(річ)], слоти, {річ["id"]: кат[річ["id"]]}, с)
    z = next((x for x in зн if x.get("правило") == "K-PAL-03"), None)
    print("ФАКТ · схему обрала «%s» → %s %.2f · %s · блокує=%s · чия_схема=%s"
          % (ім, z["сила"], z["сила_нп"], z["регістр"], z["регістр"] == "гейт", z.get("чия_схема")))
    assert (z["регістр"] == "гейт") == (ім != "stylist"), z
