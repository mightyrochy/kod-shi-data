"""Повтор записаного концерту: розбіжність, виправлення й вичерпаний повтор."""
import json, os, pathlib, sys
sys.path.insert(0, os.environ.get("E2_SOURCES", str(pathlib.Path(__file__).resolve().parents[1])))
import мовний_шар as М


def main():
    """Надрукувати факти з тих самих відповідей для ДО й ПІСЛЯ."""
    файл = pathlib.Path(__file__).resolve().parents[2] / "аудит/проби/Е2-ремонт-шар/записи.json"
    сцена = json.loads(файл.read_text(encoding="utf8"))[0]
    сирий = next(в["відповідь"] for к, в in сцена["відповіді"].items() if "seed3_01_" in к)
    вхід = dict(розмова=dict(нове=сцена["слова"]), відповідь_моделі=сирий)
    перша = json.loads(М.мова(вхід))
    об, _ = М._обʼєкт(сирий)
    виправлено = json.loads(json.dumps(об))
    виправлено["update"]["occasion"]["value"] = "theatre"
    виправлено["update"]["formality"] = "neat"
    результати = []
    for назва, відповідь in (("повтор тієї самої", сирий), ("виправлена форма", json.dumps(виправлено))):
        р = json.loads(М.мова(dict(вхід, відповідь_моделі=відповідь, перша_відповідь=сирий, завершити_договір=True)))
        п = М.паспорт_з_шару(р["внутрішня"], {}, слова_ходу=сцена["слова"], частини=р["частини"])["паспорт"]
        результати.append(п.get("подія") == "рок-концерт у клубі" and п.get("місце") == "клуб")
        print(json.dumps(dict(випадок=назва, повтор=перша.get("повтор"), запасний=bool(р.get("запасний")),
                              нагода=п.get("нагода"), подія=п.get("подія"), місце=п.get("місце"),
                              ошатність=п.get("ошатність")), ensure_ascii=False))
    return 0 if all(результати) and перша.get("повтор") and "occasion" in перша["повтор"] and "formality" in перша["повтор"] else 1


if __name__ == "__main__":
    sys.exit(main())
