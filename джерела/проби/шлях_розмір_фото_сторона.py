"""ЧИ ВЛАЗИТЬ ЗАПИТ, КОЛИ ФОТО ЇДЕ ПІД ЗАДАЧУ (наряд Л-2, вада 5/8 → PR #349).

Текст беремо РЕАЛЬНИМ пайплайном (bridge, повний каталог), розмір фото — виміром
у Chromium (`аудит/проби/фото_сторона_симв.js`, кадр телефонної деталізації, JPEG
q 0.7): 1568 px → 203 340 / 376 588 симв., 1024 → 111 956 / 186 392, 768 →
74 436 / 112 748, 512 → 42 380 / 55 696. Друкує розмір запиту на ДВА її фото
(спідниця + чоботи) до правки (обидва боком МАКС_СТОРОНА_П) і після (боком задачі).
Запуск: cd джерела && python3 проби/шлях_розмір_фото_сторона.py"""
import json, os, re, sys
_К = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _К); os.chdir(_К)
import bridge as B, feed as Ф

вх = json.load(open("стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
текст = len(r["руки"]["1"])
показ = open("показ.html", encoding="utf-8").read()
стеля = int(re.search(r"СТЕЛЯ_ВХОДУ_СИМВ\s*=\s*(\d+)", open("worker.js", encoding="utf-8").read()).group(1))
ВИМІР = {1568: (203340, 376588), 1024: (111956, 186392), 768: (74436, 112748), 512: (42380, 55696)}
сторона = lambda ім: int(re.search(r"const %s = (\d+)" % ім, показ).group(1))

print("стеля моста: %d симв · текст промпта руки 1 (bridge, повний каталог): %d симв" % (стеля, текст))
def рядок(ім, тексту, бік, фото=2):
    низ, верх = ВИМІР[бік]
    а, б = тексту + фото * низ, тексту + фото * верх
    print("  %-34s текст %6d + %d фото по %4d px = %6d…%6d симв  %s"
          % (ім, тексту, фото, бік, а, б, "влазить" if б <= стеля else "HTTP 413"))
    return б <= стеля

print("ДО правки (обидва фото боком МАКС_СТОРОНА_П = %d):" % сторона("МАКС_СТОРОНА_П"))
до_склад = рядок("складання руки 1", текст, 1568)
до_викл0 = рядок("виклик 0 (паспорт)", 17331, 1568)
print("ПІСЛЯ правки (її річ — боком %d px, її кадр на повний зріст — %d px):"
      % (сторона("СТОРОНА_ФОТО_РЕЧІ_П"), сторона("СТОРОНА_ФОТО_ЛЮДИНИ_П")))
по_склад = рядок("складання руки 1", текст, сторона("СТОРОНА_ФОТО_РЕЧІ_П"))
по_викл0 = рядок("виклик 0 (паспорт)", 17331, сторона("СТОРОНА_ФОТО_РЕЧІ_П"))
л, р = ВИМІР[сторона("СТОРОНА_ФОТО_ЛЮДИНИ_П")], ВИМІР[сторона("СТОРОНА_ФОТО_РЕЧІ_П")]
print("  %-34s текст   1054 + кадр %4d px + 2 речі по %4d px = %6d…%6d симв"
      % ("приміряння", сторона("СТОРОНА_ФОТО_ЛЮДИНИ_П"), сторона("СТОРОНА_ФОТО_РЕЧІ_П"),
         1054 + л[0] + 2 * р[0], 1054 + л[1] + 2 * р[1]))
print("     найдорожчий випадок приміряння в стелю не влазить — і його зменшує вже")
print("     `вмістити_запит_П` сходинками, а не відмова моста 413")
assert not до_склад and not до_викл0, "проба міряє ваду: до правки два фото не влазили"
assert по_склад and по_викл0, "після правки обидва запити мусять влазити з запасом"
