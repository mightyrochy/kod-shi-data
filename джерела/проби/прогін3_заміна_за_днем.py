"""Прогін3-погода-й-дорога: річ, яку фото показує не для її погоди чи дороги, опис називає на заміну (`swap.why="day"`).
Ланцюг стенда (`стенд_вх.json`, `каталог_brief.xml`), як ФОТО-1 × ВИБІР-2 у `тест_протоколу.py`: складання → вибір →
опис зі swap на взуття (чи річ на місці з аргументу) за днем. ДО: причини «day» нема — заміна відкинута, річ лишається. ПІСЛЯ: код шукає заміну
того самого виду й судить її; нема — рядок картки каже, чого бракує. Запуск: cd джерела && python3 проби/<цей файл>"""
import os, sys, json, tempfile
sys.path.insert(0, os.getcwd())
import bridge as B, feed as F
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), сід=3, каталог=F.каталог_на_диску("каталог_brief.xml"),
          кеш_кольорів=os.path.join(tempfile.gettempdir(), "кеш_живого_шляху.json"))
if not os.path.exists(вх["кеш_кольорів"]):
    json.dump({}, open(вх["кеш_кольорів"], "w"))
м = lambda ім, d: json.loads(B.виклик(ім, json.dumps(d, ensure_ascii=False)))
пул = м("запити", вх)["пакети"]["1"]["пул"]
о = [dict(ід="о%d" % (і + 1), підпис="t", речі=[пул[с][і]["н"] for с in ("верх", "низ", "взуття", "сумка", "шарф", "верхній_шар")])
     for і in (0, 1)]
в = м("від_моделі", dict(вх, текст_моделі=json.dumps(dict(версія="1", образи=о), ensure_ascii=False)))
вб = м("від_моделі", dict(вх, ітерація=2, відповідь="ВИБІР_V1", вибір_над=в["вибір_над"],
                          текст_моделі=json.dumps(dict(версія="1", обрано=в["вибір_над"]["образи"][0]["ід"]))))["вибір"]
взуття = вб["ід"][int(sys.argv[1]) if len(sys.argv) > 1 else 2]      # аргумент — місце речі в образі (0 — верх)
оп = dict(вх, ітерація=2, відповідь="ОПИС_ВІДПОВІДЬ_V1", ід=вб["ід"], інші_образи=[x["ід"] for x in в["образи"]])
т = lambda **з: json.dumps(dict(version="1", text="t", how_to_wear=[], wrong_photos=[], **з), ensure_ascii=False)
р = м("від_моделі", dict(оп, текст_моделі=т(swap=dict(item=вб["номери"][взуття], why="day"))))
з = р.get("заміна") or {}
print("swap why=day на річ", взуття, "→ стан:", з.get("стан"), "· відмова:", з.get("відмова"),
      "· запасних:", len(з.get("запасні") or []), "· рядок картки:", json.dumps(з.get("повідомлення"), ensure_ascii=False)[:160])
if з.get("запасні"):
    зп = dict(річ=з["річ"], чому=з["чому"], запасні=[x["id"] for x in з["запасні"]])
    н = м("від_моделі", dict(оп, заміна_запасні=зп, текст_моделі=т(swap=dict(
        item=вб["номери"][взуття], why="day", to=з["запасні"][0]["н"]))))["заміна"]
    print("друге звернення з першою запасною → стан:", н.get("стан"), "· річ лишилась:", взуття in (н.get("ід") or вб["ід"]))
