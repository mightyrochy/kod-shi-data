"""У файлі стоїть паспорт, на якому прогін НЕ йшов.

Знахідка ділянки 3/8, перемірена тут із другого боку: `спільне.паспорт` прогону
береться з живого `ПАСПОРТ_П` у мить запису, а справжній паспорт прогону лежить
поруч, усередині `етапи.виклики[].запит.текст`. Друкує обидва.
"""
import json
import pathlib

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]


def подія_запиту(текст):
    і = текст.find('"подія":')
    if і < 0:
        return None
    хвіст = текст[і + 8:]
    return хвіст[: хвіст.find(",")].strip().strip('"')


for ф in sorted((КОРІНЬ / "аудит" / "тести" / "власник_2026-09-25").glob("verdykty-*.json")):
    д = json.loads(ф.read_text(encoding="utf-8"))
    print(ф.name)
    for п in д["прогони"]:
        с = п["спільне"]
        у_файлі = (с.get("паспорт") or {}).get("подія")
        знайдено = []
        for в in п["вердикти"]:
            for к in (в.get("етапи") or {}).get("виклики") or []:
                п_з = подія_запиту((к.get("запит") or {}).get("текст") or "")
                if п_з:
                    знайдено.append((в.get("рука"), к.get("крок"), п_з))
        print("   розклад", с.get("розклад"), "· у файлі «подія» =", json.dumps(у_файлі, ensure_ascii=False))
        if not знайдено:
            print("      паспорта в записаних запитах нема (руки 3–4 — проза; або збірка старіша"
                  " за поле `запит.текст`) — звірити нема з чим")
        for рука, крок, п_з in знайдено:
            print("      рука %s · %s · у ЗАПИТІ до моделі «подія» = %s  %s"
                  % (рука, крок, json.dumps(п_з, ensure_ascii=False),
                     "← РОЗБІГЛОСЬ" if п_з != у_файлі else "збігається"))
