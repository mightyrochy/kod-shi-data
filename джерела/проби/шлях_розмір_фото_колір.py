# -*- coding: utf-8 -*-
"""ЧИ НЕСЕ ЗМЕНШЕНЕ ФОТО КОЛІР (наряд Л-2: «вимір кольору коду не має змінитися»).

Пікселі дає Chromium тим самим шляхом, що показ (`аудит/проби/фото_колір_сторона.js`:
кадр → JPEG заданої сторони q 0.7 → ≤128×128 RGB, як `пікселіРечіП`), а міряє їх той
самий `річ_з_фото.виміряти`, що й у продукті. База — кадр ЯК Є (сторона 0). Сторона,
на якій слово кольору розійшлось із базою, для запиту не годиться: саме так обрано
`СТОРОНА_ФОТО_РЕЧІ_П`. Друкує факт.
Запуск: cd джерела && python3 проби/шлях_розмір_фото_колір.py [пікселі.jsonl]
   (без файла проба сама кличе Chromium; PW=<шлях> — інший бінарник)"""
import json, os, re, subprocess, sys
_К = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _К)
import річ_з_фото as РФ

if len(sys.argv) > 1:
    рядки = open(sys.argv[1], encoding="utf-8").read().splitlines()
else:
    п = subprocess.run(["node", os.path.join(_К, "..", "аудит", "проби", "фото_колір_сторона.js")],
                       capture_output=True, text=True)
    if п.returncode:
        print("Chromium не дав пікселів:", (п.stderr or "")[-300:]); sys.exit(2)
    рядки = п.stdout.splitlines()

показ = open(os.path.join(_К, "показ.html"), encoding="utf-8").read()
сторони = {ім: int(з) for ім, з in re.findall(r"const (СТОРОНА_ФОТО_\w+_П) = (\d+);", показ)}
у_запитах = set(сторони.values())
print("сторони, якими показ шле її фото у виклики:", сторони)
база, спір = {}, []
for рядок in рядки:
    з = json.loads(рядок)
    в = РФ.виміряти({"дані": з["дані"], "ширина": з["ширина"], "висота": з["висота"]})
    слово = в.get("слово")
    if not з["сторона"]:
        база[з["річ"]] = слово
    print("%-34s %s → hex %s · слово %s%s"
          % (з["річ"][:34], ("кадр як є" if not з["сторона"] else "%4d px" % з["сторона"]),
             в.get("hex"), слово, "   ← ця сторона в запитах" if з["сторона"] in у_запитах else ""))
    if з["сторона"] and слово != база.get(з["річ"]):
        спір.append((з["річ"], з["сторона"], база.get(з["річ"]), слово))
print("розійшлось із кадром як є:", спір or "нема")
print("розійшлось на сторонах, якими показ шле фото:", [с for с in спір if с[1] in у_запитах] or "нема")
assert рядки and база, "пікселів нема — міряти нічого"
assert not [с for с in спір if с[1] in у_запитах], "на цій стороні код прочитав би інший колір"
