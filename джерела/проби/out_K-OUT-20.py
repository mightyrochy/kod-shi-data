# -*- coding: utf-8 -*-
"""K-OUT-20 (тренч — захист від дощу, не від холоду).

ЧОМУ БУВ ЛИШЕ СЛІД: правило вмикається температурою нижче +10 °C, а батарея
ганяє офісні +18. При +18 тренч і є тренч — мовчання правильне.
ЩО ПОКАЗУЄ ПРОБА: при +5 °C рядок стоїть у `вердикт.образи[0].знахідки`, і його
сила неперервно росте з падінням температури (при −2 вона вдвічі більша)."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
вх["сценарій"].update(темп_c=5, опади="ні")
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
к = з["кандидати"]
# річ береться з КАТАЛОГУ пакета, не лише з пулу: ознака, під яку писане правило,
# трапляється в 49 тренчів і 73 плащі з 618, і `перевірити_від_моделі` законно судить річ поза
# кандидатами (вона лише лягає в `поза_кандидатами`) — тим самим шляхом, яким у
# продукт заходить річ, знайдена моделлю в повному каталозі.
ціль = next(c for c in кат.values() if c.get("слот") == "верхній_шар" and (c.get("тип_верхнього") in ("тренч", "плащ")))
ід = [ціль["id"]] + [(к.get(сл) or [{}])[0].get("id") for сл in ("сукня", "взуття")
                     if (к.get(сл) or [])]
print("верхній шар:", ціль["назва"][:52])
print("ознака входу:", "тип «%s» · теплова вісь: %s" % (ціль.get("тип_верхнього"),
      __import__("outer").ТЕПЛОВІ_ФУНКЦІЇ.get(ціль.get("тип_верхнього"))))
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
р = next((z for z in (о.get("знахідки") or []) if z.get("правило") == "K-OUT-20"), None)
print("K-OUT-20 у вердикті:", "НЕМА" if not р else
      "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:62]))
print("речі рядка:", (р or {}).get("речі"), "· регістр", (р or {}).get("регістр"))
for t in (5, -2):
    _в = json.loads(B.виклик("від_моделі", json.dumps(
        dict(вх, сценарій=dict(вх["сценарій"], темп_c=t), ід=ід), ensure_ascii=False)))
    _з = ((_в.get("вердикт") or {}).get("образи") or [{}])[0].get("знахідки") or []
    _р = next((z for z in _з if z.get("правило") == "K-OUT-20"), None)
    print("%+3.0f°C → сила %s" % (t, (_р or {}).get("сила_нп")))
