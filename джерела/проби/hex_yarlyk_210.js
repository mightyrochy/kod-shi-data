/* З-5б (рядок 210): машинний слід на картці — ЯРЛИК, не лише значення. Жива локальна
   модель (`qwen/qwen3.5-9b`, сід 7, руки 3–4) пише «колір графіт (hex #2C2F33)»; чистка
   показу знімала `#2C2F33` і порожні дужки, а «(hex )» лишалось — шість разів на одній
   картці (знімок `z5b_hex_na_kartsi_ruka4_seed7.jpg`). Проба бере `безМашинногоСліду`
   ДО (origin/main) і ПІСЛЯ (робоче дерево) і друкує факт на рядках самої моделі.
   Рядки — з `аудит/тести/2026-09-24_прохід_1.md` (сирих `vidpovidi/` у git нема).
   Запуск із теки `джерела`: node проби/hex_yarlyk_210.js */
const fs = require("fs"), { execFileSync } = require("child_process");
const ВИТЯГ = /const безМашинногоСліду = [\s\S]*?\.trim\(\);/;
function чистка(html, мітка) {
  const m = html.match(ВИТЯГ);
  if (!m) throw new Error("не знайдено `безМашинногоСліду` у " + мітка);
  return eval("(" + m[0].replace(/^const безМашинногоСліду = /, "").replace(/;$/, "") + ")");
}
const до = чистка(execFileSync("git", ["show", "origin/main:джерела/показ.html"], { encoding: "utf8" }), "origin/main");
const після = чистка(fs.readFileSync(__dirname + "/../показ.html", "utf8"), "робоче дерево");
/* Рядки моделі: як вона їх написала (1–2) і як вони дійшли до картки в звіті (3–5). */
const РЯДКИ = [
  "колір графіт (hex #2C2F33), тканина щільний трикотаж",
  "колір пісок (hex #D9C7A7)", "колір мятний (hex )", "колір графіт (hex )", "колір пісок (hex )",
  "база олива (HEX: #5E6B4B) поруч із теракотою", "колір теракота (hex-код #B2553B)",
  "колір олива (rgb(94,107,75))",
];
const СЛІД = /\b(?:hex|rgba?|hsla?|lch|lab|cmyk)\b|#[0-9a-fA-F]{6}\b|\(\s*[,;:·.–—-]*\s*\)/i;
let дс = 0, пс = 0;
console.log("рядків моделі: %d", РЯДКИ.length);
for (const р of РЯДКИ) {
  const d = до(р), a = після(р);
  if (СЛІД.test(d)) дс++;
  if (СЛІД.test(a)) пс++;
  console.log("  %s\n     ДО    %j%s\n     ПІСЛЯ %j%s", р, d, СЛІД.test(d) ? "   ← слід" : "",
              a, СЛІД.test(a) ? "   ← слід" : "");
}
console.log("машинний слід лишився: ДО %d з %d → ПІСЛЯ %d з %d", дс, РЯДКИ.length, пс, РЯДКИ.length);
console.log("слова людини цілі: %s", РЯДКИ.every(р =>
  (р.match(/[а-яіїєґ']{3,}/gi) || []).filter(с => !/^hex$|^rgba?$|^hsla?$|^код\w*$/i.test(с))
    .every(с => після(р).includes(с))) ? "так" : "НІ");
