# -*- coding: utf-8 -*-
"""М-5 п.6: токени (і час — з MODEL) ходу розмови з 10 ходів (`м5_десять_ходів.json`), до і після. «До» — два
виклики мовної моделі на хід: перекладач входу (`промпт_входу`) і перекладач репліки (`промпт_репліки`); «після» —
один хід розмови (`промпт_розмови`). «Сталий початок» — токени незмінної частини, яку кешує провайдер: у перекладача
входу — усе до «СЛОВА:», у ходу розмови — увесь «task». TOKENIZER=<tokenizer.json> — інакше оцінка (2.6 симв/ток).
Кеш префікса — як у провайдера, на кожен вид промпта свій: MODEL_URL_VHID / _REPLIKA / _ROZMOVA (інакше MODEL_URL).
Запуск: cd джерела && TOKENIZER=… [MODEL=… MODEL_URL=…] python3 проби/м5_хід_токени.py"""
import json, os, sys, statistics
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import мова_спільне as С
М, Т = С.М, None
if os.environ.get("TOKENIZER"):
    from tokenizers import Tokenizer; Т = Tokenizer.from_file(os.environ["TOKENIZER"])
ток = lambda s: len(Т.encode(s, add_special_tokens=False).ids) if Т else round(len(s) / 2.6)
def сек(промпт, роль):
    С.АДРЕСА = (os.environ.get("MODEL_URL_" + роль) or os.environ.get("MODEL_URL") or С.АДРЕСА).rstrip("/"); return С.модель(промпт)[1]
ВІДПОВІДЬ = ("Записала. Якщо хочеш, розкажи ще трохи про цей вихід: чи хочеш привертати увагу, який макіяж плануєш "
             "і які прикраси візьмеш — а можна й ні, образи зберу й так.")
п, історія, її, теми, ряд = {}, [], [], [], []
for н, х in enumerate(json.load(open(os.path.join(С.ТУТ, "м5_десять_ходів.json"), encoding="utf-8")), 1):
    її.append(х["вона"])
    вхід = М.промпт_входу("scenario", х["вона"], {"offered_topics": теми} if теми else None)
    після = М.промпт_розмови({"розмова": {"нове": х["вона"], "історія": історія}, "сценарій": {}, "паспорт": п})
    дельта = М.прийняти_вхід("scenario", json.dumps(х["після"]))["внутрішня"]
    ш = json.loads(М.мова({"паспорт_з": дельта, "сценарій": {}, "паспорт": п, "слова_розмови": її, "частини": {"need": "none", "text": "Записала."}}))
    репліка = М.промпт_репліки({"recorded": {к: v for к, v in дельта.items() if к != "quotes"}, **({"advice_topics": ш["теми_поради"]} if ш["теми_поради"] else {})})
    с_до = с_піс = 0.0
    if С.МОДЕЛЬ:
        с_до = сек(вхід, "VHID") + сек(репліка, "REPLIKA"); с_піс = сек(після, "ROZMOVA")
    ряд.append((н, ток(вхід) + ток(репліка), ток(вхід.split("\nСЛОВА:\n")[0]), ток(після), ток(після.split(', "profile":')[0]), с_до, с_піс))
    п, теми = ш["паспорт"], ш["теми_поради"]
    історія += [{"хто": "людина", "текст": х["вона"]}, {"хто": "ші", "текст": ВІДПОВІДЬ}]
print("хід  до: токенів (2 виклики) · з них сталий початок входу   після: токенів (1 виклик) · сталий початок" + ("   с до · с після" if С.МОДЕЛЬ else ""))
for н, до, сп_до, піс, сп_піс, с1, с2 in ряд:
    print("%3d  %6d · %6d            %6d · %6d%s" % (н, до, сп_до, піс, сп_піс, "   %5.1f · %5.1f" % (с1, с2) if С.МОДЕЛЬ else ""))
до_р, піс_р = sum(r[1] for r in ряд), sum(r[3] for r in ряд)
print("РАЗОМ 10 ходів: до %d токенів у %d викликах · після %d токенів у %d викликах (%+.0f %%); нових (не з кешу) до %d · після %d%s" % (
    до_р, 2 * len(ряд), піс_р, len(ряд), 100.0 * (піс_р - до_р) / до_р, до_р - sum(r[2] for r in ряд), піс_р - sum(r[4] for r in ряд),
    " · секунд до %.0f · після %.0f" % (sum(r[5] for r in ряд), sum(r[6] for r in ряд)) if С.МОДЕЛЬ else ""))
print("токенізатор:", os.environ.get("TOKENIZER") or "оцінка 2.6 симв/ток")
