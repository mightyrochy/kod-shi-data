"""КОЛО-РОЛІ-3 (наряд 2.1-Б, умова): речі-слова, чий вердикт тону за проєктом (а') стає «так → невідомо» на зрізі суду,
лишаються в пулі руки 1? Пул руки 1 бере річ-слово рядком із дугою, коли `описує_річ` ≠ «ні» і `частка_вікна` > 0
(`композитор_слоти._збір_слота`). Дуги: ролі 5 схем × 12 якорів і вікна сімей стенда й ж1–ж9; рядок — дуга з L*, C*
0–100, 0–150 (лише тон). Друкує пари слово × дуга, що змінили вхід у пул ДО → ПІСЛЯ, і 5 «синій» з аркуша 2.1-А.
`--проєкт` — прототип (а') поверх коду, як `коло_ролі_проєкт.py`. Запуск із джерела/: python3 проби/коло_ролі_пул_слів.py"""
import json, glob, math, sys, collections as K; sys.path.insert(0, ".")
import bridge as B, colorspace as cs, колір_річ as КР, колір_відношення as КВ, палітра_схеми as ПС, palettes as ПЛ, фід_добір as ФД
вх0 = json.load(open("стенд_вх.json", encoding="utf-8")); B.виклик("запити", json.dumps(вх0, ensure_ascii=False))
слова = [r for r in B.каталог_останнього_пакета() if КР.вікно_речі(r) and КР.нейтраль_меж(r) == "ні"]
ролі = {д for i in range(12) for з in ПС.СХЕМИ.values() for д in з["тон"](cs.з_кола_художника(30.0 * i)).values() if isinstance(д, tuple)}
жінки = [вх0] + [dict(вх0, шкіра=Ж["skin"][0], волосся=Ж["hair"], очі=Ж["eyes"]) for Ж in
                 (json.load(open(f, encoding="utf-8")) for f in sorted(glob.glob("../аудит/проби/жінки/ж*.json")))]
вікна = {tuple(д) for вх in жінки for с, дд in ПЛ.палітра_практична(B._features(вх)[0])["вікна"]["сім_ї"].items() if с != "очі" for д in дд}
СИНІ = {"ж-15625@wearme.ua", "ж-14778@wearme.ua", "ж-12648@maxa.ua", "ж-16007@wearme.ua", "ж-15460@wearme.ua"}
def зняти():
    КР._ДУГИ_ВІКНА.clear(); ФД._ЧАСТКА_КЕШ.clear(); В = {}
    for x, (мн, дд) in ((x, м) for x in слова for м in (("ролі", ролі), ("вікна", вікна))):
        for д in дд:
            q = dict(L_min=0, L_max=100, C_min=0, C_max=150, h_from=д[0], h_to=д[1]); вк = КР.вікно_речі(x)
            В[(x["id"], д, мн)] = (КР.у_дугах_кола(x, [д], КВ.КІНЕЦЬ_ЗГАСАННЯ), ФД.описує_річ(x["lab"], q, вікно=вк) and ФД.частка_вікна(вк, q) > 0)
    return В
ДО = зняти()
if "--проєкт" in sys.argv:
    край = lambda d, пів, σ: 0.5 * (1.0 + math.erf((пів - d) / (σ * math.sqrt(2.0))))
    згас = lambda C: min(math.degrees(2 * math.asin(min(1.0, КВ.ΔH_КРАЮ / (2 * max(C, 1e-6))))), КВ.ЗАПАС_ПРИГЛУШЕНИХ) / КВ._Z_КІНЦЯ
    def сила_в_дузі(р, дуга):
        if р is None or р["дуга"] is None: return КВ.НЕВІДОМО
        (ц, пів), σ = КВ._параметри_дуги(дуга), (згас(р["C"][0]), згас(р["C"][1])); д = КВ._розкид_дуг(р["дуга"], (ц, ц))
        return (min(край(д[1], пів, с) for с in σ), max(край(д[0], пів, с) for с in σ))
    КВ.сила_в_дузі = сила_в_дузі; КВ.сила_точки_в_дузі = lambda C, h, д: край(КВ._кут(h, КВ._параметри_дуги(д)[0]), КВ._параметри_дуги(д)[1], згас(C))
ПІСЛЯ, Л = зняти(), K.Counter()
for к, (в0, п0) in ДО.items():
    в1, п1 = ПІСЛЯ[к]; Л[(к[2], "суд %s→%s" % (в0, в1))] += в0 != в1; Л[(к[2], "пул %s→%s" % (п0, п1))] += п0 != п1
    if в0 == "так" and в1 == "невідомо": Л[(к[2], "так→невідомо: у пулі ПІСЛЯ %s" % п1)] += 1
    if к[0] in СИНІ and в0 != в1: Л[("синій 2.1-А", "%s→%s, у пулі %s→%s, речей %d" % (в0, в1, п0, п1, len(СИНІ)))] += 1
print("слів %d, дуг ролей %d, вікон %d, %s" % (len(слова), len(ролі), len(вікна), "прототип (а')" if "--проєкт" in sys.argv else "код"))
for к, v in sorted((к, v) for к, v in Л.items() if v): print("  %-10s %-70s %5d" % (*к, v))
