# -*- coding: utf-8 -*-
"""K-COL-06 (нейтралі мають сімʼї) — ціле, перевірено пробою.

Корпус (тема-4:6097): «холодна сімʼя (чорний, білий, сірі, нейві) і тепла (кемел,
беж, коричневий, крем, олива, хакі); крос-комбінації потребують ясного кроку
світлоти. Температура білого (оптичний проти вершкового) іде за температурою
образу й підтоном людини. FORCE: default — знижено зі strong, прогін 2».
ТРИ ВИРОБНИКИ, І ВОНИ НА РІЗНИХ ШЛЯХАХ: `нейтраль()` (членство в сімʼї — читають
усі), `нейтралі_крос` (крос-пара без кроку — за гейтом площі), `білі` (два різні
білі) — цей на живому шляху, бо площі не потребує. Проба бере саме його.
Запуск із теки `джерела`: `python3 проби/col_K-COL-06.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import реєстр_правил as РЕЄСТР, колір_образу as КО
import outfit as O, композитор_річ as КМ

L_мін, C_макс = РЕЄСТР.C["біле_вікно"]; b_т, b_х = РЕЄСТР.C["b_нейтралі"]
у_вікні = lambda L, C, з: L >= L_мін and C <= C_макс
вх, r, кат, спец = ПВ.стенд(гілка=0)
# ── ВИМІР, А НЕ СЛОВО КРАМНИЦІ (рядок 149) ────────────────────────────────────
# Доти проба брала перші-ліпші речі вікна, і після рядка 141 (#231) вони приходили
# з полем `колір_не_вимір`: колір зі слова — це ВІКНО лексикону, а не точка, тож
# «вершковий» і «оптичний» ставали такими за побудовою. Правило це чесно побачило
# й замовкло — знахідки не стало взагалі, бо з двох «невідомо» пари не виходить.
# Тепер проба стверджує ОБИДВІ гілки окремо й на своєму вході.
вимір = lambda з: not з.get("колір_не_вимір")
теплий = ПВ.з_каталогу(кат, "верх", lambda L, C, h, з: у_вікні(L, C, з) and вимір(з) and з["lab"][2] > b_т)
оптичний = ПВ.з_каталогу(кат, "низ", lambda L, C, h, з: у_вікні(L, C, з) and вимір(з) and b_х <= з["lab"][2] <= b_т)
слово = ПВ.з_каталогу(кат, "верх", lambda L, C, h, з: у_вікні(L, C, з) and not вимір(з))
слово2 = ПВ.з_каталогу(кат, "низ", lambda L, C, h, з: у_вікні(L, C, з) and not вимір(з))
print("вікно білого: L* ≥ %.0f, C* ≤ %.0f · вісь температури b*: тепле > %.1f, холодне < %.1f"
      % (L_мін, C_макс, b_т, b_х))
for ярл, x in (("вершковий", теплий), ("оптичний", оптичний)):
    print("   %-10s «%s» b*=%.1f · сімʼя «%s» · вимір"
          % (ярл, x["назва"][:34], x["lab"][2], КО.нейтраль(tuple(x["lab"]))))
хвіст = [x["id"] for с in ("взуття", "сумка") for x in (r["кандидати"].get(с) or [])[:1]]
зн, _ = ПВ.знахідки(вх, [x["id"] for x in (теплий, оптичний)] + хвіст)
print("1) ВИМІР обох білих · K-COL-06: %s" % ПВ.рядок(зн, "K-COL-06"))
z = next((x for x in зн if x.get("правило") == "K-COL-06"), None)
assert z and z["сила"] == "soft" and z["регістр"] == "репліка", z
assert КО.нейтраль(tuple(теплий["lab"])) == "тепла", теплий["lab"]
assert КО.нейтраль(tuple(оптичний["lab"])) == "ахроматична", оптичний["lab"]
print("       ремонт: %s" % z["ремонт"])
# ── 2) ТІ САМІ МІСЦЯ СЛОВОМ КРАМНИЦІ: не мовчання, а «без входу» з названим полем ──
# аудит/ПРОДУКТ.md п.4. Шукати це у `знахідки` марно — і саме тому проба доти й падала:
# `вердикт_моделі._питання_або_нуль` відкидає регістр «питання» з ключа ранжування
# (це запит на дані, не зауваження), а везе його ОКРЕМИЙ канал `питання` — той, що
# стає блоком «код не знає» на картці. Проба стверджує обидва боки: сам вердикт
# правила й те, що він доїжджає до жінки.
ід2 = [x["id"] for x in (слово, слово2)]
зн2, вм2 = ПВ.знахідки(вх, ід2 + хвіст)
речі2 = [КМ._у_річ(dict(кат[i]), кат[i]["слот"], вх.get("тіло")) for i in ід2 + хвіст]
z2 = next(x for x in КО.білі(O.елементи(речі2, "у приміщенні"), "uncontrolled", None)
          if x.get("правило") == "K-COL-06")
print("2) ті самі місця СЛОВОМ крамниці · вердикт правила: %s %.2f · %s · без входу: %s"
      % (z2["сила"], z2["сила_нп"], z2["регістр"], z2["без_входу"]))
assert z2["сила"] == "питання" and z2["регістр"] == "питання" and z2["сила_нп"] == 0.0, z2
assert z2["без_входу"] == "колір_не_вимір", z2
assert not any(x.get("правило") == "K-COL-06" for x in зн2), "питання не місце в ключі ранжування"
q = next(x for x in (вм2.get("питання") or []) if x.get("правило") == "K-COL-06")
коди = [с.get("code") for с in ((q.get("повідомлення") or {}).get("statements") or [])]
print("   доїхало до жінки: канал «питання» · %s · коди %s"
      % ((q.get("повідомлення") or {}).get("kind"), коди))
assert (q.get("повідомлення") or {}).get("kind") == "card_code_unknown", q
assert "cannot_tell_two_different_whites" in коди, коди
assert set(ід2) <= set(q.get("речі") or []), q
print("   бракує: %s" % z2["бракує"][:88])
