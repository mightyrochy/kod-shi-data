# -*- coding: utf-8 -*-
"""K-OUT-26 / K-OUT-32 дістали канал 3: ремонт пропонує річ лише коли вона в гардеробі.

ДО: `ремонти(…, гардероб)` брала канал 3 у сигнатуру й НЕ ЧИТАЛА його (таблиця прогалин
PR #182, §4 п.13), тож «узяти власний пояс поверх» звучало однаково для тієї, у кого
пояс є, і для тієї, у кого його нема. «ДО» тут не з пам'яті: старий модуль береться з
git і виконується поруч із новим. Читач каналу 3 не новий — той самий, що в
`аксесуари_структура.команди_розкладки`: речі образу плюс гардероб, збіг за `слот`."""
import sys, types, pathlib, subprocess
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import верхнє_стан as НОВЕ

БАЗА = sys.argv[1] if len(sys.argv) > 1 else "df48bdf"
_дж = subprocess.run(["git", "show", "%s:джерела/верхнє_стан.py" % БАЗА],
                     capture_output=True, text=True, check=True, cwd=_КОРІНЬ.parent).stdout
СТАРЕ = types.ModuleType("верхнє_стан_до")
exec(compile(_дж, "<%s>" % БАЗА, "exec"), СТАРЕ.__dict__)
ОБРАЗ = [dict(слот="верхній_шар", назва="пуховик довгий", тип_верхнього="пуховик"),
         dict(слот="низ", назва="спідниця міді", тип="спідниця")]
ГАРДЕРОБИ = [("канал 3 не передали", None),
             ("гардероб є, пояса нема", [dict(слот="взуття", назва="черевики")]),
             ("гардероб із поясом", [dict(слот="пояс", назва="ремінь шкіряний 3 см")])]


def рядок(мітка, мод, гардероб):
    з = next(з for з in мод.ремонти(ОБРАЗ, темп_c=-5, тривалість_год=2.0, гардероб=гардероб)
             if з["правило"] == "K-OUT-26")
    print("   %-24s %s %.2f · %s" % (мітка, з["сила"], з["сила_нп"], з["суть"][:52]))
    print("   %-24s ремонт: %s" % ("", " | ".join(з["ремонт"][1:])[:104]))
    return з["сила"], з["сила_нп"], tuple(з["ремонт"])

print("образ: пуховик без пояса при −5 °C · правило K-OUT-26")
до = [рядок("ДО · " + м, СТАРЕ, г) for м, г in ГАРДЕРОБИ]
після = [рядок("ПІСЛЯ · " + м, НОВЕ, г) for м, г in ГАРДЕРОБИ]
assert len(set(до)) == 1, "ДО канал 3 не міняв НІЧОГО — саме це й була прогалина"
assert len(set(після)) == 3, "ПІСЛЯ кожен стан каналу 3 дає свій ремонт"
assert після[1][1] < після[2][1], "без пояса ремонт слабший, ніж коли пояс є"
assert "докупити пояс" in " ".join(після[1][2]), "без речі ремонт називає ціну покупки"
