"""Друкує збіг чипів, джерела й справжнього брифу на трьох профілях у двох гамах."""
import json
import pathlib
import sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import bridge as М
import міст_основи as МО
import brief as Б
import palettes as П


def головна():
    """Вимірює перемикання через справжній міст, не підмінюючи кольори пакета."""
    пакети, записи = [], []
    оригінал = МО.пакет
    def записати(*арг, **іменовані):
        """Зберігає пакет, який справді використав екран."""
        пакет = оригінал(*арг, **іменовані)
        пакети.append(пакет)
        return пакет
    МО.пакет = записати
    try:
        for шкіра, очі, волосся in (("#f1d0b5", "#3b2417", "#16110e"), ("#bb8561", "#56816b", "#70503b"), ("#5a3a2a", "#5c8499", "#d4b887")):
            for гама in ("приглушені", "насичені"):
                екран = json.loads(М.палітри(dict(шкіра=[шкіра], очі=очі, волосся=[волосся], обхвати={}, зріст=168, вибір_кольору=dict(насиченість=гама))))
                пакет = пакети[-1]
                бриф = Б.бриф(пакет, гілка=None)["текст"]
                г = next(г for г in екран["гілки"] if г["схема"] == "аналогова")
                пр = next(г["спец"]["палітра_практична"] for г in пакет["палітри"]["розвилка"] if г["схема"] == "аналогова")
                поєднання = next(п for п in пр["поєднання"] if п["прийом"] == "аналогова")
                записи.append(dict(профіль=[шкіра, очі, волосся], гама=гама, чип=г["зразки"], низ=next(р["зразок"] for р in г["ролі"] if р["слот"] == "низ"), джерело=г["зразки"] == [к["hex"] for к in поєднання["кольори"]], бриф=all(р["зразок"] in бриф for гілка in екран["гілки"] for р in гілка["ролі"] if р["слот"] in ("верх", "низ", "взуття", "сумка")), поєднання_бриф=П.для_пакета(пр)["поєднання"]))
    finally:
        МО.пакет = оригінал
    print(json.dumps(записи, ensure_ascii=False, indent=2))
    return all(з["джерело"] and з["бриф"] for з in записи) and all(а["чип"] != б["чип"] for а, б in zip(записи[::2], записи[1::2]))


if __name__ == "__main__":
    sys.exit(0 if головна() else 1)
