"""Л-14: чи судить хроматичне слово (зелений, синій, червоний…) вимір БЕЗ тону і що через це проходило.
Точки — дизайни, як у `vikna_vzhytku.py`. «Чужа пара» — майже нейтральний (C* < `ТОН_ВІД_C`) вимір одного
слова, що влазить у вікно слова ІНШОЇ сім'ї: доти таке слово брало його мовчки.
Запуск: cd джерела && python3 проби/ton_khromatychnoho.py"""
import collections, os, re, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_розбір as FR, фід_збагачення as FZ, verify as V, colorspace as CS
from фід_фото import _спільні_фото, чужий_кадр, _файл_фото; from фід_розбір import _СЕП_КОЛЬОРУ
оф = FR.читати_yml(feed.каталог_на_диску())[0]; зб, сп = FZ.читати_збагачення(), _спільні_фото(оф)
ТОК = re.compile(r"[a-zа-яёєіїґ']+")
одне = lambda ч: not re.search(r"[\[(]", ч) and sum(1 for x in ТОК.findall(ч.lower().replace("-", " "))
                                                     if V.назва_кольору(x) or V.слово_крамниці(x)) <= 1
т = collections.defaultdict(dict)
for o in оф:
    z = зб.get(o["id"]); ч = [x.strip() for x in _СЕП_КОЛЬОРУ.split(o.get("колір_сирий") or o.get("колір_назва") or "") if x.strip()]
    if not FZ._збагачення_придатне(z) or (z.get("версія") or 1) < 2 or len(ч) != 1 or not одне(ч[0]):
        continue
    lab, ск = FZ._lab_з_hex(z["колір_основний"].get("hex")), V.слово_крамниці(ч[0])
    if lab is not None and ск and not чужий_кадр(z.get("фото"), сп.get(o.get("магазин") or o["id"].split("@")[-1]) or {}):
        т[ск["ім"]].setdefault(_файл_фото(z["фото"]), CS.lch(lab))
хром = [с for с, в in V.ЛЕКСИКОН.items() if в[4] is not None and с not in V.МЕТАЛИ]
без_вжитку, без_тону = sorted(с for с in хром if с not in V.ВЖИТОК), [с for с in хром if V.вікно_вжитку(с)[4] is None]
діра, нп = [с for с in хром if V.вікно_вжитку(с)[2] < V.ТОН_ВІД_C], {
    с: [p for p in т.get(с, {}).values() if p[1] < V.ТОН_ВІД_C] for с in хром}
влазить = lambda в, p: в[0] <= p[0] <= в[1] and в[2] <= p[1] <= в[3]
пари = [(с, ч, p) for с in хром for p in нп[с] for ч in хром
        if V.сім_я_слова(ч) != V.сім_я_слова(с) and влазить(V.вікно_вжитку(ч), p)]
лишилось = [x for x in пари if V._тон_не_суперечить(x[2][2], V.вікно_вжитку(x[1])[4], x[2][1])]
своїх, усіх = sum(V._тон_не_суперечить(p[2], V.вікно_вжитку(с)[4], p[1]) for с in хром for p in нп[с]), sum(map(len, нп.values()))
print("ФАКТ · хроматичних слів %d; вікно вжитку БЕЗ тону — %d %s; без вікна вжитку (замало дизайнів, "
      "тон бере зразок слова з ЛЕКСИКОН) — %d: %s" % (len(хром), len(без_тону), без_тону or "(жодного)",
      len(без_вжитку), ", ".join("%s %d" % (с, len(т.get(с, {}))) for с in без_вжитку)))
print("ФАКТ · слів, чия підлога хроми нижча за ТОН_ВІД_C %d (вікно бере майже нейтральний вимір) — %d із %d; "
      "майже нейтральних дизайнів %d" % (V.ТОН_ВІД_C, len(діра), len(хром), усіх))
print("ФАКТ · ДРІЖ_AB %g: пар «слово × чужий майже нейтральний вимір» %d → %d (зникло %d, %.0f%%); своїх майже "
      "нейтральних лишилось %d із %d (%.0f%%)" % (V.ДРІЖ_AB, len(пари), len(лишилось), len(пари) - len(лишилось),
      100 * (len(пари) - len(лишилось)) / len(пари), своїх, усіх, 100 * своїх / усіх))
print("ФАКТ · названий випадок (#409, кадр polo_chocolate речі ж-03040@solmar.com.ua, графіт C* 7.7 тон 25°) "
      "проти слова «зелений»: %s" % V.перевірити((22.82, 6.96, 3.32), ім="зелений")["вердикт"])
