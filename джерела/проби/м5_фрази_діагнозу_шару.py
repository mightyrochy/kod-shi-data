# -*- coding: utf-8 -*-
"""Рядок 168 (п.12): скільки фраз коду й кириличних ід лишилось у діагнозі мовного шару показу — на main,
на голові гілки й у робочому дереві. Місця: ід записів шару (`напрям`, `де`, `питання_до`, аргумент `де`
викликів шару), `рядкиШаруП`, рядки шару в `ЗБ.діагноз` і в записі виклику (`відмова`, `причина`), кидки
мостів. Друкує лічбу літералів із кирилицею; кидки поза мостами (HTTP, стеля, pyodide, «на фото не…») — окремо.
Запуск із теки `джерела`: `python3 проби/м5_фрази_діагнозу_шару.py`."""
import re, subprocess
КИР, ЛІТ = re.compile(r"[а-яіїєґА-ЯІЇЄҐ]"), re.compile(r"'((?:\\.|[^'\\])*)'|\"((?:\\.|[^\"\\])*)\"")
ШАР = r"(?:мовоюП|перекластиП|реплікоюП|ходомРозмовиП|повідомленнямП|мовоюКарткуП|мовоюКарткуОцінкиП)\("
ЗНАК = re.compile(r"шар|layer|паспорт випадку|passport|розмова:|turn ·|мовний гейт|language_gate|переклад коментаря")
СЕР = re.compile(r"HTTP|стелю виводу|pyodide|дзеркало|картинки|полотно|токена|жодна рука|на фото не|не впізнано")
def дужки(т, п):                                   # кінець виразу з відкритою дужкою перед п
    г = 1
    while г and п < len(т):
        г += {"(": 1, "[": 1, ")": -1, "]": -1}.get(т[п], 0); п += 1
    return т[:п]
def кир(вираз): return [a or b for a, b in ЛІТ.findall(вираз) if КИР.search(a or b)]
def лічба(т):
    т = re.sub(r"/\*.*?\*/", "", т, flags=re.S)
    ід = [л for м in re.finditer(r"(?:напрям|де):\s*'[^']*'|питання_до\s*=[^;]+;", т) for л in кир(м.group(0))]
    for м in re.finditer(ШАР, т):                   # останній аргумент виклику шару — `де`
        в = дужки(т[м.end():], 0); ост = re.split(r",\s*(?![^()]*\))", в[:-1])[-1]
        ід += кир(ост) if not re.search(r"\.' \+|'\w+\.'", ост) else []
    ряд = re.search(r"function рядкиШаруП\(.*?\n\}", т, re.S)
    діаг = [дужки(т[м.end():], 0) for м in re.finditer(r"ЗБ\.діагноз\.push\(", т)]
    діаг = [л for в in діаг if ЗНАК.search(в) for л in кир(в)]
    запис = [л for м in re.finditer(r"(?:відмова|причина|коментар_внутрішня_чому)(?::|\s*=(?!=))\s*(?=['\"(])[^;}]+", т)
             for л in кир(re.sub(r"\[\s*'[^']*'\s*\]", "", м.group(0)))]   # ['ключ'] — ключ, не фраза
    кидки = [кир(дужки(т[м.end():], 0)) for м in re.finditer(r"throw new Error\(", т)]
    мости = sum(1 for к in кидки if к and not СЕР.search(" ".join(к)))
    return dict(ід=len(ід), рядкиШаруП=len(кир(ряд.group(0))) if ряд else 0, діагноз=len(діаг),
                запис=len(запис), кидки_мостів=мости, кидки_поза_мостами=sum(1 for к in кидки if к) - мости), ід
def файл(дж, ім): return (subprocess.run(["git", "show", "%s:джерела/%s" % (дж, ім)], capture_output=True,
                                          text=True).stdout if дж else open(ім, encoding="utf-8").read())
ПАЙ = re.compile(r"не_взято_кодом\", \[\]\)\.append\(|не_взято_кодом\"\) or \[\]\) \+ \[|def вигадка_рядком\(.*?return \(", re.S)
def пайтон(т): return sum(len(кир(дужки(т[м.end():], 0))) for м in ПАЙ.finditer(т))   # фрази коду в Python-рядках звіту
for назва, джерело in (("main", "origin/main"), ("голова", "HEAD"), ("робоче", None)):
    л, ід = лічба(файл(джерело, "показ.html"))
    л["python_не_взято"] = пайтон(файл(джерело, "паспорт_нагоди.py")) + пайтон(файл(джерело, "мовний_шар.py"))
    print("%-7s %s · кириличні ід: %s" % (назва, " · ".join("%s %d" % кв for кв in л.items()), sorted(set(ід)) or "—"))
