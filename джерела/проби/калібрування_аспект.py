# -*- coding: utf-8 -*-
"""КЛ-347: частка ребер «ні», чий аспект поза темою правила, — до і після `ребро_враховано`.
Ребра — справжні знахідки карток стенда (`REBRA_OUT`, `рв6_стенд.js`) і вивантажені файли
вердиктів `аудит/тести/**/verdykty*.json`. Дотики аспектів — таблиця нижче (стенд усі вердикти
ставить «як є»). До: кожне ребро «ні» враховане. Після: враховані лише ребра теми аспекту.
Запуск: cd джерела && python3 проби/калібрування_аспект.py /tmp/rebra.json"""
import glob, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import вердикт_моделі as В, ід_правил as ІП
ребра = [(е["правило"], е["напруга"]) for п in json.load(open(sys.argv[1])) for е in п["ребра"]]
for ф in glob.glob("../аудит/тести/**/verdykty*.json", recursive=True):
    ребра += [(е["правило"], е["напруга"]) for пр in json.load(open(ф))["прогони"]
              for в in пр.get("вердикти", []) for е in (в.get("ребра") or [])]
в = {"речі": [{"id": "x"}], "знахідки": [{"правило": р, "сила_нп": н} for р, н in ребра]}
НІ, ЯКЩО, ТАК = "не вдягну", "вдягну, якщо змінити одну річ", "вдягну як є"   # напис картки, як іде в міст
СЦЕНИ = [(НІ, {"reasons": [а]}, а) for а in В.СІМЇ_АСПЕКТУ] + [
    (НІ, {"mine": "mine"}, "mine_not_worn"), (ЯКЩО, {"reasons": ["colour", "price"]}, "colour+price"),
    (НІ, {}, "без аспекту"), (ТАК, {"good": ["colour"]}, "як є + colour")]
print("ребер: %d · сцена | було поза темою | стало поза темою (з врахованих) | не враховано (причини)" % len(ребра))
for верд, з, ім in СЦЕНИ:
    тема = В._сімї_аспектів(з.get("reasons") or з.get("good") or [])
    названо = bool(з.get("reasons") or з.get("good"))
    поза = lambda р: названо and (ІП.сімʼя(р) or "") not in тема
    до = sum(поза(р) for р, _ in ребра)
    рядки = В.вердикт_у_ребра(верд, в, "", зведено=з)
    ост = sum(поза(е["правило"]) for е in рядки if е["враховано"])
    чому = {}
    for е in рядки:
        if not е["враховано"]: чому[е["чому_без"].split(":")[0]] = чому.get(е["чому_без"].split(":")[0], 0) + 1
    print("%-14s %-8s %5.1f %% → %5.1f %%  враховано %3d/%d  %s" % (ім, верд, 100 * до / len(ребра),
          100 * ост / max(1, sum(е["враховано"] for е in рядки)), sum(е["враховано"] for е in рядки), len(рядки), чому))
