# -*- coding: utf-8 -*-
"""K-ACC-13 (віднімання — операція; «мінус один аксесуар» — не число).

ДО ПРАВКИ два розриви, і обидва мовчазні.
  1. `перевірити_образ` кладе `віднімання` ОКРЕМИМ ключем аксесуарної гілки, а
     `composer._оцінити` читає з гілки рівно `ворота` й `преференції` — тобто
     повноцінна знахідка (правило, сила, сила_нп, суть, речі, ремонт) не доходила
     ні до моделі, ні до жінки. Це та сама смерть у третьому каналі, яку вчора
     знято для команд і ремонтів верхнього шару.
  2. `_рід_елемента` стоїть на чотирьох полях, яких аксесуар у цьому фіді не має:
     `метал` не пише ніхто (`feed.метал` існує й не викликається), `візерунок` і
     `блиск` на аксесуарах порожні, `near` після перенормування дає 0.067 і сумці,
     і хустці — завжди нижче за поріг 0.3. Виміряно: образ із пʼятьма аксесуарами
     → рід «інше» ×5, дублів нема, знахідки нема НІ РАЗУ.
ПІСЛЯ: рід «гучний колірний акцент» стоїть на `C` елемента (її ставить
`outfit.гучність` на кожному проході) з порогом `hi_C` = 40.0 — у пакеті таких
аксесуарів 121. Два гучні аксесуари витрачають ОДИН бюджет хроми, і рядок стоїть
у `вердикт.образи[0].знахідки`."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, колір_образу as КО

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
гучні = [c for c in кат
         if c.get("слот") in ("прикраси", "шарф", "сумка", "пояс", "головний_убір")
         and c.get("lab") and (КО.гучність(tuple(c["lab"])).get("C") or 0) >= 40]
двоє = [c for c in гучні if c["слот"] == "прикраси"][:2]
база = [next(c for c in кат if c.get("слот") == сл) for сл in ("сукня", "взуття", "сумка")]
print("гучних аксесуарів (C ≥ hi_C 40.0) у пакеті: %d" % len(гучні))
for c in двоє:
    print("   %-10s «%s» C=%.0f" % (c["слот"], c["назва"][:40], КО.гучність(tuple(c["lab"]))["C"]))
о = ((json.loads(B.виклик("від_моделі", json.dumps(
    dict(вх, ід=[c["id"] for c in база + двоє]), ensure_ascii=False))
    ).get("вердикт") or {}).get("образи") or [{}])[0]
р = next((z for z in (о.get("знахідки") or []) if z.get("правило") == "K-ACC-13"), None)
print("K-ACC-13 у вердикті:", "НЕМА" if not р else
      "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:58]))
print("ремонт називає, ЩО зняти:", str((р or {}).get("ремонт"))[:92])
assert р, "прохід на віднімання мусить доїжджати у вердикт"
