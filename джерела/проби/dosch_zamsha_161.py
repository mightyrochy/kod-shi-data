"""Рядок 161 (А): замша в дощ. Каталог_повний. (1) Взуття, яке K-WEA-05 бачить замшею, а hard-вето
K-WEA-01 — ні: ДО — старе слово K-WEA-01 (`волокно or матеріал`, значення `ВОЛОГІ_ВЕТО`), ПІСЛЯ —
справжній `суд_погода.погода` на елементі речі (дощ, надворі). (2) Що нове відсічення знімає з пулу
на стенд_вх зі сценарієм «прогулянка в парку, +15 °C, опади так». (3) Текст K-WEA-05 на кросівках
ж-09011 при +16 °C у дощ і при −3 °C. Запуск із `джерела`: PYTHONPATH=. python3 проби/dosch_zamsha_161.py"""
import json, sys; sys.path.insert(0, ".")
import bridge as B, outfit as O, суд_погода as СП, аксесуари_погода as АП, міст_пакет as МП, пакет_моделі as ПМ
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
взуття = [c for c in кат.values() if c.get("слот") == "взуття"]
старе = lambda c: any(v in (c.get("волокно") or c.get("матеріал") or "").lower() for v in СП.ВОЛОГІ_ВЕТО)
def вето01(c):
    E = O.елементи([dict(c, hex=c.get("hex") or "#333333", площа=0.1, near=0.05)])
    return any(з["правило"] == "K-WEA-01" and з["суть"].startswith("замша")
               for з in СП.погода(E, темп_c=15, опади="дощ", стан="надворі"))
бачить05 = [c for c in взуття if АП.відмовляє_у_волозі(c)]
до = [c for c in бачить05 if not старе(c)]
після = [c for c in бачить05 if not вето01(c)]
print("взуття в каталозі %d · K-WEA-05 бачить замшею/нубуком/велюром %d" % (len(взуття), len(бачить05)))
print("K-WEA-05 бачить, K-WEA-01 — ні: ДО %d → ПІСЛЯ %d" % (len(до), len(після)))
for c in до[:5]:
    print("   %s «%s» · верх «%s» · волокно «%s»" % (c["id"], c["назва"][:60], c.get("матеріал_верху"), c.get("волокно")))
сц = dict(вх["сценарій"], нагода="прогулянка", місце="парк", темп_c=15, опади="так", година=11, дрес_код=None)
МП._КЕШ_ПАКЕТА.clear(); _сл, _ор = {}, ПМ._жорстке_відсічення
def _лік(r, *а):
    п = _ор(r, *а); п and п.startswith("замша") and _сл.setdefault(r.get("слот"), set()).add(r.get("id")); return п
ПМ._жорстке_відсічення = _лік
json.loads(B.виклик("запити", json.dumps(dict(вх, сценарій=сц), ensure_ascii=False)))
пак = list(МП._КЕШ_ПАКЕТА.values())[-1]
в = пак.get("відсічено") or {}
print("пул «парк, +15 °C, опади так»: відсічено за дощем %s (різних речей по слотах, з доборами: %s) · приклад %s" % (
    (в.get("лічба") or {}).get("замша, нубук чи велюр у дощ — вето корпусу", 0), {к: len(в_) for к, в_ in _сл.items()},
    (в.get("приклади") or {}).get("замша, нубук чи велюр у дощ — вето корпусу")))
з = кат.get("ж-09011@kasandra.ua")
for t in (16, -3):
    зн = [x for x in АП.сезон_і_погода([dict(з, слот="взуття")], темп_c=t, опади="дощ") if x["правило"] == "K-WEA-05"]
    print("K-WEA-05 на ж-09011 при %+d °C: %s" % (t, зн[0]["суть"] if зн else "—"))
