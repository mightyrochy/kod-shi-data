"""Що код ВИМІРЯВ на її фото і яке слово кольору куди поїхало далі.

Модель називає слово (`річ_з_фото.СХЕМА_РЕЧІ.колір`), код міряє пікселі в її
рамці (`річ_з_фото.виміряти`). У пул і в промпти рук іде слово ВИМІРУ
(`запис_каталогу`, `руки_без_коду.її_речі`), а жінці в розмові — слово МОДЕЛІ."""
import sys, os, json
К = os.path.join(os.path.dirname(__file__), "..")
sys.path.insert(0, К)
import річ_з_фото as РФ

Ф = os.path.join(К, "..", "аудит", "тести", "власник_2026-09-25",
                 "verdykty-0phxvk-2026-09-25-2012.json")
d = json.load(open(Ф, encoding="utf-8"))
п = [x for x in d["прогони"] if str(x["спільне"].get("розклад")) == "3421"][0]
речі = (п["спільне"]["паспорт"] or {}).get("речі_з_фото") or []
for р in речі:
    в = р.get("вимір") or {}
    кл = в.get("кластери") or []
    print("%s «%s» — слот %s" % (р["ід"], р.get("назва"), р.get("слот")))
    print("   слово моделі: %-14s | вимір: %-12s %s | частка %s, маска %s, пікселів %s"
          % (р.get("колір"), в.get("слово"), в.get("hex"), в.get("частка"), в.get("маска"), в.get("пікселів")))
    print("   кластери: %s" % ", ".join("%s %s %.0f%%" % (c["слово"], c["hex"], c["частка"] * 100) for c in кл))
    if в.get("другий"):
        print("   другий кластер: %s %s %s — у пул не їде" % (в["другий"]["слово"], в["другий"]["hex"], в["другий"]["частка"]))
    з = РФ.запис_каталогу(р)
    print("   у пул: id %s, колір «%s» (%s), джерело %s" % (з["id"], з.get("колір"), з.get("hex"), з.get("джерело_кольору")))
print()
print("промпт рук 3–4 (руки_без_коду.її_речі, П-1 — кодами, без слота):")
import руки_без_коду as РБК
print(json.dumps(РБК.її_речі(речі), ensure_ascii=False))
