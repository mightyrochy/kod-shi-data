"""Носій поля не виводиться з власного переліку місць чи стану пальта."""
import sys
sys.path.insert(0, ".")
import аксесуари_структура as А, місце_речі as М

def головна():
    """Друкує носія й опис невідомого місця без вигаданого нуля."""
    for слово, видно in ((None, 1), ("так", 1), ("ні", 1), ("так", None), ("так", 0)):
        р = dict(id="ш", річ="шарф", слот="шарф", місце="шия", місця=["шия", "волосся"])
        if слово:
            р["місце_стилістки"] = dict(біля_обличчя=слово, слова="як вдягнено")
        р["місце_речі"] = dict(М.записати(р), видно=видно)
        носій = А.носій_приобличчевого_поля([р])
        print("носій", слово, видно, "→", bool(носій))
        assert bool(носій) == (слово == "так" and видно == 1)
    assert А.носій_приобличчевого_поля([dict(слот="окуляри")])
    р = dict(р, місце_речі=М.записати(dict(слот="шарф")))
    з = А._віднімання_утримано({"рід": [р, dict(р, річ="другий шарф")]})
    print("опис:", з["чому"])
    assert "невідомо" in з["чому"] and "0.00" not in з["чому"]

if __name__ == "__main__":
    головна()
