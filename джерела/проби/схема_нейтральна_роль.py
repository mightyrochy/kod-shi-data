# -*- coding: utf-8 -*-
"""Рядок 5890: K-PAL-03 «кольорова річ на нейтральній ролі» досяжна на образі.

Схема «нейтрали+акцент» тримає домінанту й секунданта нейтральними; спека такого слота
дуги не має, тож суд читав `дуга` = None і гілка не спрацьовувала ніколи. Проба бере пул
стенда під цю схему, кожну кольорову річ (`нейтраль_меж` = «ні») зі слота домінанти чи
секунданта судить `схема_образу` і рахує знахідки; один образ — ще й повним `від_моделі`.
Запуск із теки `джерела`: `python3 проби/схема_нейтральна_роль.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import суд_від_моделі as СМ, колір_річ as КР

вх, r, кат, спец = ПВ.стенд(гілка=None, схема="нейтрали+акцент")
слоти = dict(спец.get("slots") or спец.get("слоти") or {}, _схема=спец.get("схема"))
нейтр = [с for с, v in слоти.items() if isinstance(v, dict) and v.get("тон_ролі") == "нейтраль"
         and v.get("роль") in ("домінанта", "секундант")]
кольорові = [dict(кат[x["id"]], слот=с) for с in нейтр for x in (r.get("кандидати") or {}).get(с) or ()
             if x.get("id") in кат and КР.нейтраль_меж(кат[x["id"]]) == "ні"]
зн = [z for річ in кольорові for z in СМ.схема_образу([річ], слоти, {річ["id"]: річ}, None)
      if z.get("ярлик") == "кольорова річ на нейтральній ролі"]
print("ФАКТ · схема %s · нейтральні ролі %s · кольорових речей у них у пулі %d · K-PAL-03 «на "
      "нейтральній ролі» %d" % (спец.get("схема"), нейтр, len(кольорові), len(зн)))
assert нейтр and len(кольорові) == len(зн) > 0, (нейтр, len(кольорові), len(зн))
річ = next((x for x in кольорові if x["слот"] == "верх"), кольорові[0])
решта = [ПВ.взяти(r, кат, с, (lambda L, C, h, зап: КР.нейтраль_меж(зап) == "так") if с == "низ"
                  else (lambda *a: True)) for с in ("низ", "взуття", "сумка") if с != річ["слот"]]
повні, _ = ПВ.знахідки(вх, [річ["id"]] + [x["id"] for x in решта if x])
z = next((x for x in повні if any(з.get("code") == "scheme_slot_neutral_item_coloured"
                                  for з in x.get("заяви") or ())), None)
print("ФАКТ · від_моделі на «%s» (%s): %s" % (річ.get("назва", "—")[:40], річ["слот"],
      ПВ.рядок([z] if z else [], "K-PAL-03")))
assert z, "повний шлях не дав знахідки"
