# -*- coding: utf-8 -*-
"""K-OUT-23 (довжини дублянки в сантиметрах — єдина числова шкала теми).

ЧОМУ БУВ ЛИШЕ СЛІД: правило вмикається типом «дублянка»/«шуба» або рівнем
«стегно»/«коліно». Дублянок у каталозі НУЛЬ, а офісний образ батареї верхнього
шару такого типу не брав.
ЩО ПОКАЗУЄ ПРОБА: шуба з оголошеним рівнем → рядок у вердикті, і він друкує
обидві шкали поруч — сантиметри джерела й частку зросту, яка їх спростовує."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
вх["сценарій"].update(темп_c=5, опади="ні")
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
к = з["кандидати"]
# річ береться з КАТАЛОГУ пакета, не лише з пулу: ознака, під яку писане правило,
# трапляється в 44 шуби з 618; дублянок у каталозі нема, і `перевірити_від_моделі` законно судить річ поза
# кандидатами (вона лише лягає в `поза_кандидатами`) — тим самим шляхом, яким у
# продукт заходить річ, знайдена моделлю в повному каталозі.
ціль = next(c for c in кат.values() if c.get("слот") == "верхній_шар" and (c.get("тип_верхнього") in ("шуба", "дублянка") and c.get("довжина_рівень")))
ід = [ціль["id"]] + [(к.get(сл) or [{}])[0].get("id") for сл in ("сукня", "взуття")
                     if (к.get(сл) or [])]
print("верхній шар:", ціль["назва"][:52])
print("ознака входу:", "тип «%s», рівень «%s»" % (ціль.get("тип_верхнього"), ціль.get("довжина_рівень")))
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
р = next((z for z in (о.get("знахідки") or []) if z.get("правило") == "K-OUT-23"), None)
print("K-OUT-23 у вердикті:", "НЕМА" if not р else
      "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:62]))
print("речі рядка:", (р or {}).get("речі"), "· регістр", (р or {}).get("регістр"))
print("дві шкали в одному рядку:", str((р or {}).get("суть"))[:70])
