# -*- coding: utf-8 -*-
"""Проба: що каже хрома, зміряна по СВІТЛІШІЙ половині пікселів маски.

Тінь на тканині з'їдає хрому: темно-синя річ у півтіні дає C* < 8 і лягає у
вікно «чорний»/«графіт» — межа вікон ЛЕКСИКОНУ тут ні до чого, бо вимір і
справді ахроматичний. `жнива_v2.світліша_половина` міряє ту саму маску по
світліших пікселях; ця проба показує, скільком речам це дало б інше слово і в
який бік. Вікна `verify.ЛЕКСИКОН` не чіпаються — друкується факт, не рішення.
"""
import io, json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ)
import verify as V
import colorspace as CS

д = json.load(io.open(os.path.join(ТУТ, "аудит", "збагачення_v2_вибірка.json"), encoding="utf-8"))
ахром = {с for с, в in V.ЛЕКСИКОН.items() if not в[4]}      # вікна без дуги тону
рядки = []
for р in д["речі"]:
    св = (р.get("вимір") or {}).get("світліша")
    осн = (р.get("запис") or {}).get("колір_основний")
    if not св or not осн:
        continue
    кл = [к for к in р["вимір"]["кластери"] if к["слово"] == осн["слово"]]
    C0 = round(CS.lch(tuple(кл[0]["lab"]))[1], 1) if кл else None
    рядки.append((р.get("слот"), р["id"], осн["слово"], C0, св["слово"], св["C"], св["тон"]))
інше = [р for р in рядки if р[2] != р[4]]
з_ахром = [р for р in інше if р[2] in ахром and р[4] not in ахром]
print("речей із виміром %d · світліша половина називає інше слово %d · із них ахроматичне → тон %d"
      % (len(рядки), len(інше), len(з_ахром)))
for слот, ід, сл0, C0, сл1, C1, тон in sorted(з_ахром, key=lambda x: -x[5]):
    print("  %-13s %-27s %s C*%s → %s C*%s (тон %s)" % (слот, ід, сл0, C0, сл1, C1, тон))
print("решта змін слова (тон → тон або тон → ахроматичне): %d" % (len(інше) - len(з_ахром)))
