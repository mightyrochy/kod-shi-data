"""Е3 Ч-Г: суд тих самих образів ДО/ПІСЛЯ — виміри збережено, ремонту-заміни в знахідках нема.

Запуск: python3 проби/е3_чг_без_ремонту.py [джерела бази]; без бази — лише перевірка «ПІСЛЯ»."""
import json, os, subprocess, sys
sys.path.insert(0, os.getcwd())
import colorspace as cs, fit as ПС, pipeline as PL
T = ПС.тіло(168, dict(плечі=98, груди=92, талія=74, стегна=99, високе_стегно=88))
F = cs.features(cs.hx("#deb295"), cs.hx("#f1dbaa"), cs.hx("#759087"))
р = lambda i, с, h, н, т, **к: dict(id=i, слот=с, hex=h, назва=н, тип=т, **к)
ОБРАЗИ = [[р("a", "верх", "#8a7f74", "Светр", "светр", верх_см=140, низ_см=95), р("b", "низ", "#5b4e4d", "Штани", "штани", верх_см=100, низ_см=5),
           р("c", "взуття", "#22201e", "Черевики", "черевики", верх_см=10, низ_см=0)],
          [р("d", "сукня", "#c9b8a0", "Сукня міді", "сукня", верх_см=140, низ_см=47), р("e", "верхній_шар", "#2b2b2b", "Пальто", "пальто", верх_см=140, низ_см=33),
           р("f", "взуття", "#e8d9c4", "Балетки", "балетки", верх_см=6, низ_см=0), р("g", "сумка", "#a0522d", "Сумка", "сумка")],
          [р("h", "верх", "#e9e4d8", "Гольф об'ємний", "светр", верх_см=140, низ_см=70, оверсайз=True, крій="oversize"),
           р("i", "верх", "#c8c2b5", "Водолазка", "гольф", верх_см=140, низ_см=80), р("j", "низ", "#d6d0c4", "Спідниця максі", "спідниця", верх_см=100, низ_см=15),
           р("k", "верхній_шар", "#d9d2c3", "Пальто приталене", "пальто", крій="приталений", верх_см=140, низ_см=60),
           р("l", "взуття", "#d8c7b3", "Босоніжки", "босоніжки", верх_см=6, низ_см=0), р("m", "аксесуар", "#d9cfc0", "Шарф", "шарф"), р("n", "пояс", "#d9cfc0", "Пояс", "пояс")]]
ПОЛЯ = ("правило", "сила", "сила_нп", "поріг", "вимір", "речі")
def знахідки(в):
    """Усі знахідки-словники з правилом у вкладеному виході суду."""
    if isinstance(в, dict): return ([в] if isinstance(в.get("правило"), str) else []) + [з for х in в.values() for з in знахідки(х)]
    return [з for х in в for з in знахідки(х)] if isinstance(в, (list, tuple)) else []
def зліпок():
    вих = [з for о in ОБРАЗИ for з in знахідки(PL.перевірити_образ(F, [dict(x) for x in о], тіло=T, нагода="робота", смуга_погоди="mild"))]
    return [dict({к: з.get(к) for к in ПОЛЯ}, ремонт=bool(з.get("ремонт") or з.get("ремонт_заяви"))) for з in вих]
if __name__ == "__main__":
    стало = зліпок()
    if os.environ.get("ЧГ_JSON"): print(json.dumps(стало, default=str)); sys.exit(0)
    assert стало, "суд не дав знахідок"
    if len(sys.argv) > 1:
        було = json.loads(subprocess.check_output([sys.executable, os.path.abspath(__file__)], cwd=sys.argv[1], env=dict(os.environ, ЧГ_JSON="1")))
        key = lambda з: json.dumps({к: з[к] for к in ПОЛЯ}, ensure_ascii=False, sort_keys=True, default=str)
        assert sorted(map(key, було)) == sorted(map(key, стало)), "виміри змінились"
        print("ДО/ПІСЛЯ: знахідок %d/%d, виміри збережено; з ремонтом %d → %d" % (len(було), len(стало), sum(з["ремонт"] for з in було), sum(з["ремонт"] for з in стало)))
    else: print("ПІСЛЯ: знахідок %d, з ремонтом %d" % (len(стало), sum(з["ремонт"] for з in стало)))
