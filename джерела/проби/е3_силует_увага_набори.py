"""Повний каталог і граничні входи силуету образу й регістру уваги для звірки ваги."""
import gzip, json, os, pathlib

ВЗУТТЯ = [dict(id='взуття-%s' % к, назва='пара %s' % к, слот='взуття', hex='#202020', **({} if к is None else {'каблук_см': к}))
          for к in (None, 0.0, 2.0, 3.9, 4.0, 7.0)]


def набори():
    """(назва, модуль, функція, args, kwargs) без моделі: кожна річ каталогу й граничні пари."""
    import feed as Ф
    import outfit as О
    кеш = pathlib.Path(os.environ['TMP']) / 'е3_каталог.json.gz'
    if not кеш.exists():
        каталог = Ф.база_прогону(Ф.каталог_на_диску('каталог_повний.xml'), ліміт_фото=0)['каталог']
        with gzip.open(кеш, 'wt', encoding='utf-8') as ф:
            json.dump(каталог, ф, ensure_ascii=False)
    else:
        with gzip.open(кеш, 'rt', encoding='utf-8') as ф:
            каталог = json.load(ф)
    print('каталог', len(каталог), flush=True)
    for р in каталог:
        назва = str(р['id'])
        образи = [[р]] + ([[р, в] for в in ВЗУТТЯ] if р.get('слот') in ('низ', 'сукня') else [])
        for і, речі in enumerate(образи):
            yield '%s#%d' % (назва, і), 'суд_силует', 'силует_образу', [речі, О.елементи(речі)], {}
        Е = О.елементи([р])
        for мета in ('приховати', 'експресія'):
            for зони in (None, ['живіт'], ['ноги']):
                yield '%s@%s@%s' % (назва, мета, зони), 'регістр_уваги', 'знахідка_уваги', \
                    [Е, [р], мета], dict(зони_мети=зони)
