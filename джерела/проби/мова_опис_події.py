"""Опис події переживає перенесення коду; чужий уривок не стає подією."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import мовний_шар as М
import пакет_моделі as П
import дріт_моделі as Д


def main():
    """Звірити слова події, пріоритет явного опису й намір на вході стилістки."""
    слова = "похорон дідуся в четвер зранку"
    for поле, код, цитата in (("occasion", "funeral", слова), ("place", "funeral", слова),
                              ("occasion", "work", "робочий день в офісі")):
        р = М.прийняти_розмову(json.dumps({"update": {поле: {"value": код, "quote": цитата}}}))
        п = М.паспорт_з_шару(р["внутрішня"], {}, слова_ходу=цитата)["паспорт"]
        assert Д.випадок(П.випадок_для_пакета(п, ""))["event"] == цитата
    в = {"place": "funeral", "quotes": {"place": слова}}
    assert not М.паспорт_з_шару(в, {}, слова_ходу="вечір у театрі")["паспорт"].get("подія")
    for явна in ({"event": "вечір у театрі"}, {}):
        п = М.паспорт_з_шару(dict(в, **явна), {}, паспорт_досі={"подія": "робочий день"},
                             слова_ходу=[слова, "вечір у театрі"])["паспорт"]
        assert п["подія"] == (явна.get("event") or "робочий день")
    for намір in ("conventional", "fashion_forward", "statement"):
        фраза = "робочий день в офісі, хочу виділитися"
        в = {"place": "office", "intent": намір, "quotes": {"place": фраза, "intent": "хочу виділитися"}}
        п = М.паспорт_з_шару(в, {}, слова_ходу=фраза)["паспорт"]
        випадок = Д.випадок(П.випадок_для_пакета(п, ""))
        assert випадок["event"] == фраза and випадок["intent"] == намір
    print("Опис на коді нагоди/місця: 3/3; чужий уривок: відкинуто; пріоритет: 2/2; намір: 3/3")


if __name__ == "__main__":
    main()
