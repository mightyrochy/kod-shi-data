"""Назва її речі — поле name моделі; уривок не підміняє назви, навіть коли її немає."""
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from річ_з_фото import її_речі_шару


def main():
    """Друкує фактичні назви на межі запису й перевіряє незалежність від уривка."""
    випадки = [
        ("моєї спідниці", "спідниця", ["спідниця"]),
        ("моєї улюбленої спідниці", "спідниця", ["спідниця"]),
        ("моєї спідниці", {"value": "skirt", "free_text": "моєї спідниці"}, ["skirt"]),
        ("", {"value": "skirt", "free_text": "моєї спідниці"}, ["skirt"]),
        ("моєї спідниці", "", []),
        ("моєї спідниці", {"free_text": "спідниця", "lang": "uk"}, ["спідниця"]),
        ("моєї спідниці", {"quote": "моєї спідниці"}, []),
    ]
    збоїв = 0
    for уривок, назва, очікувані in випадки:
        речі = її_речі_шару([dict(quote=уривок, name=назва, slot="bottom", status="has")])
        фактичні = [р["назва"] for р in речі]
        print(json.dumps(dict(уривок=уривок, назва=назва, фактичні=фактичні,
                              очікувані=очікувані), ensure_ascii=False))
        збоїв += фактичні != очікувані
    print(f"випадків: {len(випадки)}; збоїв: {збоїв}")
    return int(bool(збоїв))


if __name__ == "__main__":
    raise SystemExit(main())
