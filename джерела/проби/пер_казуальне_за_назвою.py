# -*- coding: utf-8 -*-
"""ПЕР-492: чи є в 10 образах рук 1–2 казуальні речі за назвою (кеди, футболка, шорти…) — з файлів вердиктів `<база>/<нагода>_В/вердикти.txt.gz`."""
import json,re,sys,collections,gzip,os
БАЗА=sys.argv[1] if len(sys.argv)>1 else "аудит/перевірки/per_492"
КАЗ=re.compile(r"кед|кросів|шльопан|в'єтнамк|шорти|худі|футболк|шопер|пляж|спортивн|толстовк|світшот|тапочк|сланц|угги|уги\b|джинс|бомбер|сабо|crocs",re.I)
for r in ["робота","співбесіда","весілля","похорон","театр","прогулянка"]:
    d=json.load(gzip.open(os.path.join(БАЗА,r+"_В","вердикти.txt.gz"),"rt",encoding="utf-8"))
    for в in d["прогони"][0]["вердикти"]:
        р=int(str(в["рука"]))
        if р not in (1,2): continue
        зб=в["етапи"]["виклики"][0]; q=зб["запит"]["текст"]; пакет=json.loads(q[q.index("{"):])
        наз={x["n"]:x["name"] for x in пакет["pool"]}
        o=json.loads(зб["відповідь_сира"][зб["відповідь_сира"].index("{"):])["outfits"]
        різні=set(n for x in o for n in x["items"]); поз=[(n,наз.get(n,"")[:50]) for n in sorted(різні) if КАЗ.search(наз.get(n,""))]
        обр=sum(1 for x in o if any(КАЗ.search(наз.get(n,"")) for n in x["items"]))
        print(f"{r} рука{р}: образів {len(o)}, з казуальним за назвою {обр}, різних речей {len(різні)}, казуальних {len(поз)}", поз if r!="прогулянка" else "")
