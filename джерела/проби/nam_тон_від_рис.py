# -*- coding: utf-8 -*-
"""НАМІР У `palette.тон_від_рис` — виміряно: `python проби/nam_тон_від_рис.py`.

ДО: `intent` стояв у сигнатурі, `специфікація` передавала його іменем, а дуги
рис і їхній тиск виходили для conventional і statement побайтово однакові.
ПІСЛЯ: намір обирає КРАЙ огинаючої індукції (R-CHEV-14) — рівно те, що просить
`тиск_знахідка.ремонт`: «щоб ТИХІШЕ біля обличчя — Δh до 0° або 180°; щоб
ГУЧНІШЕ — до |Δh|≈пік. Який край потрібен, вирішує намір образу». Дуга несе
`під_наміром` ∈[0,1], дуги риси стоять у порядку згоди з краєм (видно на
«тріаді» — двi дуги на рису). source=protocolized: на uncontrolled рядки
фіду утримує K-PC-05."""
import sys, pathlib, json
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import bridge as B, palette as П
F, T, _зр, _kw = B._збірка(json.load(open(_К / "стенд_вх.json", encoding="utf-8")))
ДЖ, було = "protocolized", {}
for намір in ("conventional", "statement"):
    тв = П.тон_від_рис(F, "аналогова", source=ДЖ, intent=намір)
    спец = П.специфікація(F, "аналогова", ["верх", "низ", "взуття", "сумка"],
                          source=ДЖ, intent=намір)
    рядки = П._рядки_від_рис(спец)
    тр = П.тон_від_рис(F, "тріада", source=ДЖ, intent=намір)
    пн = {nm: [d["під_наміром"] for d in д["дуги"]]
          for nm, д in тв["риси"].items() if д.get("дуги")}
    сер = sum(sum(v) / len(v) for v in пн.values()) / max(1, len(пн))
    print("%-13s край «%s» (ціль Δh %.0f°) · рядків фіду %d · середнє під_наміром %.4f"
          % (намір, тв["край_наміру"]["край"], тв["край_наміру"]["ціль_Δh"],
             len(рядки), сер))
    for nm in sorted(пн):
        print("   %-9s тиск %s → під_наміром %s · тріада: перша дуга %s"
              % (nm, [d["тиск_центр"] for d in тв["риси"][nm]["дуги"]], пн[nm],
                 тр["риси"][nm]["дуги"][0]["дуга"]))
    було[намір] = (round(сер, 4), [(r.get("риса"), r["h_from"], r.get("під_наміром"))
                                   for r in рядки], [d["дуга"] for d in тр["риси"]["очі"]["дуги"]])
assert було["conventional"][0] != було["statement"][0], "намір не доїхав до дуг"
c, s = було["conventional"], було["statement"]
print("РІЗНИЦЯ Є: середнє %.4f → %.4f; рядків фіду з іншим числом %d із %d; "
      "порядок дуг «тріада» на очах %s"
      % (c[0], s[0], sum(1 for a, b in zip(c[1], s[1]) if a != b), len(c[1]),
         "перевернувся" if c[2] != s[2] else "той самий"))
