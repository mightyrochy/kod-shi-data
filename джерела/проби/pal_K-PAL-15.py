# -*- coding: utf-8 -*-
"""K-PAL-15 (поєднання всередині палітри) — від сліду до знахідки.

Корпус (тема-2:1865): стиліст видає не палітру, а трійки; вони будуються кроком
світлоти (K-COL-01), бюджетом хроми (K-COL-02: не більше одного гучного) і рівнем
контрасту людини (низький ≤ 45 L*, високий ≥ 30). Код це рахував — і лише ПРОПОНУВАВ
(`palettes.поєднання` → бриф). Чи тримає ТОЙ САМИЙ набір перевірок образ, який
склала модель, не питав ніхто.
ПІСЛЯ: логіку винесено в `palettes.набір_законний` — ОДИН емітент на два вживання
(пропозиція трійок і суд образу), інакше система пропонувала б те, що сама
відхиляє. Запуск із теки `джерела`: `python3 проби/pal_K-PAL-15.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import palettes as PAL, pipeline as PL

вх, r, кат, спец = ПВ.стенд(гілка=0, намір="statement")
П = спец["палітра_практична"]
рівень = (спец.get("слоти") and None) or "низький"
кольоровий = lambda L, C, h, _: not PL._нейтральний_тон(h, C, L)
пара = [ПВ.взяти(r, кат, с, кольоровий) for с in ("верх", "сукня", "низ", "шарф", "прикраси")]
пара = [x for x in пара if x][:2]
решта = [ПВ.взяти(r, кат, с, lambda *a: True) for с in ("взуття", "сумка")]
точки = [(ПВ.lch(кат, x["id"])[0], ПВ.lch(кат, x["id"])[1]) for x in пара]
законно, чому = PAL.набір_законний(точки, рівень)
print("кольорові речі образу: %s" % "; ".join("%s L%.0f C%.0f" % ((x["назва"] or "")[:26], *точки[i])
                                              for i, x in enumerate(пара)))
print("та сама логіка, що в трійках (`набір_законний`, контраст «%s»): %s%s"
      % (рівень, "законно" if законно else "НІ", "" if законно else " — " + чому))
ід = [x["id"] for x in пара + решта if x]
зн, _ = ПВ.знахідки(вх, ід)
print("ФАКТ · K-PAL-15: %s" % ПВ.рядок(зн, "K-PAL-15"))
z = next((x for x in зн if x.get("правило") == "K-PAL-15"), None)
assert bool(z) == (not законно), "знахідка й `набір_законний` розійшлись: %s проти %s" % (bool(z), законно)
if z:
    assert z["сила"] == "hint" and z.get("регістр"), z
    print("       ремонт: %s" % z["що_зняло_б"])
