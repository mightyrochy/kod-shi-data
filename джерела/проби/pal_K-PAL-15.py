# -*- coding: utf-8 -*-
"""K-PAL-15 (поєднання всередині палітри) — від сліду до знахідки.

Корпус (тема-2:1865): трійки будуються кроком світлоти (K-COL-01), бюджетом хроми
(K-COL-02) і контрастом людини; `palettes.набір_законний` — один емітент для трійок і суду.
З 03.10 (ФОКУС-2, п.17) суд зводить речі в ГОЛОСИ тоном: зелена сумка й сережки — відлуння
K-COMP-05, тож довільна пара з НІ знахідки не дає (рядок 1740). Проба шукає пару РІЗНИХ
голосів (НІ → знахідка є) і законну пару (знахідки нема). Запуск із `джерела`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import palettes as PAL, pipeline as PL

вх, r, кат, спец = ПВ.стенд(гілка=0, намір="statement", самозвіт={"метал": "золото"})
рівень = "низький"        # контраст стендової жінки (`palette.контраст_особи`)
кольоровий = lambda L, C, h, _: not PL._нейтральний_тон(h, C, L)
жив = lambda сл: [x for x in (r["кандидати"].get(сл) or [])
                  if ПВ.lch(кат, x["id"])[0] is not None and кольоровий(*ПВ.lch(кат, x["id"]), None)]
верхи = жив("верх") + жив("сукня")
низи = жив("низ") + жив("шарф") + жив("прикраси") + жив("головний_убір")
решта = [ПВ.взяти(r, кат, с, lambda *a: True) for с in ("взуття", "сумка")]
незаконна = законна = None
for a in верхи:
    for b in низи:
        if незаконна and законна: break
        т = [ПВ.lch(кат, a["id"])[:2], ПВ.lch(кат, b["id"])[:2]]
        ок, ч = PAL.набір_законний(т, рівень)
        if (ок and законна) or (not ок and незаконна): continue
        ід = [x["id"] for x in [a, b] + решта if x]
        зн, _ = ПВ.знахідки(вх, ід)
        z = next((x for x in зн if x.get("правило") == "K-PAL-15"), None)
        print("пара L/C %s: набір_законний=%s · ФАКТ K-PAL-15: %s" % (
            "; ".join("%.0f/%.0f" % tuple(x) for x in т), "так" if ок else "НІ — " + ч, ПВ.рядок(зн, "K-PAL-15")))
        if ок:
            assert not z, "законна пара, а знахідка є: %s" % z["суть"]
            законна = True
        elif z:
            assert z["сила"] == "hint" and z.get("регістр"), z
            print("       ремонт: %s" % z["ремонт"])
            незаконна = True
assert незаконна, "жодна НЕзаконна пара різних голосів не дала знахідки K-PAL-15 — правило мертве"
