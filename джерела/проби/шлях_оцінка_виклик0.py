"""Ділянка 8: ЩО НАСПРАВДІ ЇДЕ У ВИКЛИК 0 НА ЇЇ ПИТАННЯ ПРО ОБРАЗ. Показ дописує до промпта
паспорта довідку про застосунок і гілку «якщо її питання — про застосунок, відповідай у
відповідь_людині». Міряє частки промпта й показує, що це ЄДИНА гілка, яка дозволяє моделі
вільний текст. Запуск із `джерела`: python3 проби/шлях_оцінка_виклик0.py"""
import sys, json, re; sys.path.insert(0, '.')
import паспорт_нагоди as ПН
T = open('показ.html', encoding='utf-8').read()
ряд = lambda взір: T[:re.search(взір, T).start()].count('\n') + 1
довідка = re.search(r'const ШІ_ДОВІДКА = `(.*?)`;', T, re.S).group(1)
додаток = re.search(r"function додатокДоПаспортаП\(\)\{\n  return (.*?);\n\}", T, re.S).group(1)
текст_додатка = re.sub(r"\s*\+\s*|'|\\n", ' ', re.sub(r"\+ ШІ_ДОВІДКА.*", '', додаток, flags=re.S))
СЦЕН = dict(нагода=None, місце='зал', година=11, темп_c=18)
промпт = ПН.промпт_паспорта(СЦЕН, 'Мене цікавить чи поєднуються ці кольори між собою і чи підійдуть вони мені?',
                            фото=[dict(ід='ф1', ширина=713, висота=1568)])
print('виклик 0 на її питання з фото — частки промпта:')
print('  промпт паспорта (`промпт_паспорта`)      %6d симв.' % len(промпт))
print('  + ДОВІДКА ПРО ЗАСТОСУНОК (ШІ_ДОВІДКА)    %6d симв.  (показ.html:%d)' % (len(довідка), ряд(r'const ШІ_ДОВІДКА')))
print('  + інструкція «КРІМ ПАСПОРТА…» і стан      %6d симв.  (показ.html:%d)'
      % (len(' '.join(текст_додатка.split())), ряд(r'function додатокДоПаспортаП')))
print('  разом ≈ %d симв.; довідка — %.0f %% промпта'
      % (len(промпт) + len(довідка), 100.0 * len(довідка) / (len(промпт) + len(довідка))))
print('інструкція додатка дослівно: %s' % ' '.join(текст_додатка.split())[:330])
print('→ вільний текст жінці промпт дозволяє РІВНО в одній гілці — «питання про застосунок»;')
print('  для питання про її образ гілки нема, і модель бере ту, що є')
ключ = [c for c in ('фото', 'колір', 'палітр', 'поєдн') if c in довідка]
print('у довідці є слова %s — але це опис ЕКРАНІВ, а не дані її образу: слів «Зібрати образи» %d,'
      ' «кнопк» %d' % (ключ, довідка.count('Зібрати образи'), довідка.count('кнопк')))
print('прикладів-фраз у довідці (лапки «…»): %d — рівно те, що промпти збирача навмисно не мають'
      % довідка.count('«'))
