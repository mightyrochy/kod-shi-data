# -*- coding: utf-8 -*-
"""Проба (звірка B1-1 зі звіту Research #453): ЧИ Є В КОДІ ВХІД ДЛЯ «намисто не на краю вирізу».
Міряє, скільки типів вирізу фіду має глибину в `аксесуари_край.ГЛИБИНИ_ВИРІЗУ`, скільки прикрас
несе ланцюг, і чи є у фіді водолазка, про яку каже корпус. Друкує факт, моделі не кличе.
Запуск: python3 джерела/проби/кольє_горловина_звірка.py"""
import collections, os, sys                                                   # noqa: E401
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import аксесуари_край as АК, фід_каталог as ФК                                # noqa: E401,E402
записи = ФК._прочитати_каталог(ФК.каталог_на_диску(), ліміт_фото=0)["каталог"]
вирізи, ланцюги = collections.Counter(), collections.Counter()
for r in записи:
    в = (r.get("параметри") or {}).get("виріз_тип") or r.get("виріз_тип")
    if r.get("слот") in ("верх", "сукня", "комплект") and в:
        вирізи[в] += 1
    if r.get("слот") in АК.ЛАНЦЮГОВІ_СЛОТИ and r.get("ланцюг_см") is not None:
        ланцюги[r["слот"]] += 1
без_глибини = {в: n for в, n in вирізи.items() if в not in АК.ГЛИБИНИ_ВИРІЗУ}
з_краєм = sum(вирізи.values()) - sum(без_глибини.values())
print("верхів і суконь із названим вирізом %d · край горловини рахується для %d (%d %%) · "
      "типів без глибини: %s" % (sum(вирізи.values()), з_краєм,
                                 round(100 * з_краєм / (sum(вирізи.values()) or 1)),
                                 без_глибини or "жодного"))
print("типи вирізу фіду: %s" % ", ".join("%s %d" % t for t in вирізи.most_common()))
print("прикрас із виміряним ланцюгом: %s · разом %d"
      % (", ".join("%s %d" % t for t in ланцюги.most_common()), sum(ланцюги.values())))
# КОРПУС КАЖЕ ПРО ВОДОЛАЗКУ («водолазка → matinee 50+»), А ФІД ЇЇ НЕ НАЗИВАЄ ЖОДНОГО РАЗУ:
# найвищий виріз, який фід уміє сказати, — «стійка», і її глибина 0 см (край на основі шиї).
# Тому окремого правила водолазки код не має чим годувати, а механізм для нього вже стоїть.
print("водолазка як тип вирізу у фіді: %s · «стійка» падає на %.0f см від основи шиї"
      % ([в for в in вирізи if "водолаз" in в or "гольф" in в] or "нема",
         АК.ГЛИБИНИ_ВИРІЗУ["стійка"]))
assert not без_глибини, без_глибини        # кожен тип фіду має глибину — інакше правило мовчить
т, верх = dict(висоти={"плечі": 140.0}), dict(id="в", слот="верх", виріз_тип="стійка", назва="гольф")
кольє = lambda см: [dict(id="к", слот="кольє", ланцюг_см=см, назва="ланцюг"), верх]
print("на «стійці» (край 140.0): ланцюг 45 см → край 117.5, знахідок %d · ланцюг 8 см → "
      "край 136.0, знахідок %d (поріг зазору %s см)"
      % (len(АК.кольє_проти_горловини(т, кольє(45.0))),
         len(АК.кольє_проти_горловини(т, кольє(8.0))), АК.C["кольє_зазор_см"]))
assert not АК.кольє_проти_горловини(т, кольє(45.0))
assert len(АК.кольє_проти_горловини(т, кольє(8.0))) == 1
