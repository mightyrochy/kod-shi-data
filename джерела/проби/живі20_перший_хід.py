"""ОЦІНКА-Ж20 (#871, #874; рядки 4204, 4205, 4206, 4260): replay перших ходів ЖИВІ-18/19/20 №5–9 без моделі тим кодом,
що в теці аргументу (типово `.`): `прийняти_розмову` → `паспорт_з_шару`. На хід: що дала модель (`hour` з уривком,
`part_of_day`, `place`) і що стало в паспорт (година, пора, місце). Слова читає ПРОБА (лише щоб надрукувати уривок).
Кращим: година, яку вона назвала (і словами), — у паспорті; пора без вигаданої години; місце з її слів.
Запуск: cd джерела && python3 проби/живі20_перший_хід.py [тека джерел іншої збірки]"""
import re, subprocess, sys
sys.path.insert(0, sys.argv[1] if len(sys.argv) > 1 else "."); import мовний_шар as М
git = lambda *а: subprocess.run(["git", "-c", "core.quotepath=false", *а], capture_output=True, text=True).stdout
сире = lambda x: "%s«%s»" % (x.get("value"), x.get("quote") or "") if isinstance(x, dict) else x
година = пора_без = 0
for ж in ("18", "19", "20"):
    Г, Т = "origin/claude/zhyvi-%s" % ж, "аудит/живі_%s/А" % ж
    for ф in sorted(ф for ф in git("ls-tree", "-r", "--name-only", Г, ":/" + Т).split("\n")
                    if "_01_мовний_шар_хід" in ф and re.search(r"/0[5-9]_", ф)):
        сц, т = ф.split("/")[-3], git("show", "%s:%s" % (Г, ф))
        слова = re.search(r"ВОНА: (.*)", git("show", "%s:%s/%s/лог.txt" % (Г, Т, сц))).group(1)
        відп = т.split("── ВІДПОВІДЬ", 1)[1].split("──", 1)[1]
        u = (М._обʼєкт(відп)[0] or {}).get("update") or {}
        р = М.прийняти_розмову(відп)
        п = М.паспорт_з_шару(р["внутрішня"], {}, слова_ходу=[слова], частини=р["частини"],
                             не_взято=р.get("не_взято"))["паспорт"]
        година += п.get("година") is not None
        print("Ж%s %s | hour %s · пора %s · place %s → година %s, пора %s, місце %s" % (
            ж, сц[:22], сире(u.get("hour")), сире(u.get("part_of_day")), сире(u.get("place")),
            п.get("година"), п.get("пора"), п.get("місце")))
print("ходів з годиною в паспорті: %d" % година)
