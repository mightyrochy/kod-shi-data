"""Звіряє чинні факти речі між повним і коротким форматами без виклику моделі."""
import copy, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import pipeline as П, дріт_моделі as Д, каталог_коди as К

def перевірити(речі):
    """Друкує кількість розбіжностей у чотирьох поєднаннях перемикачів запису."""
    вад = звірок = 0
    for р in речі:
        до = copy.deepcopy(р)
        дроти = []
        for увімк in (False, True):
            К.оголосити(увімк)
            запис = П.річ_пулу(р, {})
            for короткий in (False, True):
                дріт = Д.річ(запис, короткий=короткий)
                дроти.append({п: дріт.get(п, дріт.get(з)) for п, з in К.ПОЛЯ_ЗАПИСУ.items()})
        вад += sum(д != дроти[0] for д in дроти[1:]) + (р != до)
        звірок += 4
    К.оголосити(None)
    print("речей: %d; звірок: %d; розбіжностей: %d" % (len(речі), звірок, вад))
    return вад


if __name__ == "__main__":
    розбір = dict(item_type="skirt", cut="tight", length="maxi", material="silk", fabric_kind="lace",
                  features="Distinctive shop detail", pattern="striped")
    речі = [dict(id="1", тип="сукня", крій="прямий", довжина="міді", слот="сукня",
                 рід_тканини_слово="трикотаж", погодні_матеріали=["cotton"], розбір=розбір),
             dict(id="2", розбір=розбір), dict(id="3", тип="незнайомий тип", розбір=розбір),
             dict(id="4", власна=True, матеріал="шкіра", довжина="її довжина", розбір=розбір)]
    К.оголосити(True)
    запис = П.річ_пулу(речі[-1], {})
    дріт = Д.річ(запис)
    assert дріт.get("material") == "leather" and дріт.get("length") == "її довжина"
    assert запис.get("features") == розбір["features"] and запис["розбір"].get("pattern") == "striped"
    assert "item_type" not in П.річ_пулу(речі[1], {})["ознаки_запису"]
    К.оголосити(False)
    assert К.частка_з_розбором([П.річ_пулу(речі[0], {})]) == (0, 1)
    sys.exit(bool(перевірити(речі)))
