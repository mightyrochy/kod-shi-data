"""РЕМОНТ-962 (02.10): річ із вітрини ремонту («found_for») входить в образ, навіть коли пакет витіснено з кеша.
Шлях: відповідь складання з «потрібно» → вітрина ремонту (номер речі за запитом) → відповідь ремонту з цією річчю.
Сценарій «витіснено» — між двома відповідями пакети двох інших гілок (кеш тримає 2 позиції). Нічого не викликає ззовні."""
import json, os, sys, tempfile
Д = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, Д); os.chdir(Д)
import bridge as B, feed as Ф, тест_живого_шляху as T
вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["каталог"] = Ф.каталог_на_диску(T.КАТАЛОГ)
вх["кеш_кольорів"] = os.path.join(tempfile.gettempdir(), "кеш_живого_шляху.json")
if not os.path.exists(вх["кеш_кольорів"]): json.dump({}, open(вх["кеш_кольорів"], "w"))
вик = lambda к, **x: json.loads(B.виклик(к, json.dumps(dict(вх, **x), ensure_ascii=False)))
вх["паспорт"] = dict(вик("паспорт", json_моделі=json.dumps(dict(T.ПАСПОРТ_МОДЕЛІ, намір="conventional"), ensure_ascii=False))["паспорт"]); вх["паспорт"].pop("намір", None)
вх["гілка"] = 0; з = вик("запити", пакети=1); пул = з["пакети"]["1"]["пул"]
ном = [пул[р["слот"]][0]["н"] for р in T._ядро_образу(з["кандидати"])]
в1 = вик("від_моделі", текст_моделі=json.dumps(dict(версія="1", образи=[dict(ід="о1", речі=ном)], потрібно=[dict(слот="взуття", опис="лофери чорні замша")]), ensure_ascii=False))
знайдені = [r for рч in в1["вердикт"]["вітрина"].values() for r in рч if r.get("за_запитом")]
н, ід_запиту = знайдені[0]["н"], {x["id"] for x in в1["запропоновано"]}
for назва, витіснити in (("кеш цілий", False), ("кеш витіснено", True)):
    for г in ((1, 2) if витіснити else ()): вик("запити", гілка=г, пакети=1)
    в2 = вик("від_моделі", текст_моделі=json.dumps(dict(версія="1", образи=[dict(ід="о1", речі=ном[:-1] + [н])], потрібно=[]), ensure_ascii=False), ітерація=2)
    невід = [x for p in (в2.get("розбір_блоків") or {}).get("невідомі_в_образах") or [] for x in p["невідомі"]]
    print("%-14s вітрина %s · невідомі після ремонту: %d · річ за запитом у складі образу: %s" % (назва, н, len(невід), any(і in ід_запиту for о in в2["образи"] for і in о["ід"])))
