"""КАДР-870: скільки кадрів речей дійшло до моделі на кроці опису (лог стенда рв6_стенд.js).
Запуск: python3 джерела/проби/кадр_870.py <лог.txt> [<модель_виклики.json>]
Лог: рядки «… ОПИС_V1→… (…, фото N (не дійшло M)) …»; N — усі кадри виклику, M — що не дійшли.
Друкує по виклику й разом: дійшло / не дійшло, частка втрат і причини (рядок «кадрів не дійшло…»)."""
import json, re, sys

лог = open(sys.argv[1], encoding='utf-8').read()
виклики = re.findall(r'фото (\d+)(?: \(не дійшло (\d+)\))?\)', лог)
усього = sum(int(n) for n, _ in виклики)
втрачено = sum(int(m or 0) for _, m in виклики)
for і, (n, m) in enumerate(виклики, 1):
    print(f'виклик {і}: кадрів {n}, дійшло {int(n) - int(m or 0)}, не дійшло {m or 0}')
частка = 100 * втрачено / усього if усього else 0
print(f'РАЗОМ: викликів з кадрами {len(виклики)}, кадрів {усього}, дійшло {усього - втрачено}, '
      f'не дійшло {втрачено} ({частка:.0f} %)')
причини = re.search(r'кадрів не дійшло до моделі: (\d+) · (.*)', лог)
print('причини:', причини.group(0) if причини else 'не записано (старий адаптер) або втрат нема')
if len(sys.argv) > 2:
    ж = json.load(open(sys.argv[2], encoding='utf-8'))
    print('модель_виклики.json: фото_не_дійшло =', sum(int(в.get('фото_не_дійшло') or 0) for в in ж))
