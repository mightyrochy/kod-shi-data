# -*- coding: utf-8 -*-
"""М-1, В-1/В-6: «…ДЛЯ ПОХОДУ НА КОНЦЕРТ» — ЧИ НЕ ГИНЕ ПОДІЯ БЕЗ КОДУ І ЧИ СУДИТЬ ВОНА ЇЇ РІЧ.
Друкує, чи бачить перекладач у промпті, що концерт — це код місця `theatre` (плитка «Зал»), і
для трьох відповідей перекладача — паспорт, смугу, проти якої код судить її спідницю (ошатність
6), і вердикт. Лише `мовний_шар` і `річ_з_фото.вердикт` — та сама проба на main і на гілці.
Запуск із `джерела`: python3 проби/шлях_шар_подія.py"""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import мовний_шар as МШ, сценарій as СЦ, річ_з_фото as РФ, паспорт_нагоди as ПН, colorspace as cs
from міст_вхід import _збірка, _нормалізувати_вхід

слова = "Збери образ під цю спідницю і чоботи для походу на концерт"
п_ = МШ.промпт_входу("scenario", слова)
місце = next((р for р in п_.split("\n") if р.startswith("- place")), "")
print("промпт перекладача: код місця theatre названо з «концерт» — %s; символів промпта %d"
      % ("theatre (Зал: театр, кіно, концерт" in місце, len(п_)))
F, T, _з, _к = _збірка(_нормалізувати_вхід(dict(json.load(open("стенд_вх.json")))))
спідниця = dict(ід="ф1", фото="ф1", назва="мініспідниця зі зміїним принтом", слот="низ", колір="хакі",
                ошатність=6, чия="моя", закріплена=True, вимір=dict(lab=list(cs.hx("#7d7f63")), hex="#7d7f63", слово="хакі"))
подія = {"free_text": "похід на концерт", "lang": "uk"}
for підпис, в in (("лише подія (перекладач без коду)", {"event": подія}),
                  ("подія + її смуга event_formality 4–6", {"event": подія, "event_formality": {"from": 4, "to": 6}}),
                  ("place=theatre з цитатою «концерт»", {"event": подія, "place": "theatre", "quotes": {"place": "концерт"}})):
    р = МШ.паспорт_з_шару(в, {}, None, {"речі_з_фото": [спідниця]}, речі_з_фото=[спідниця], слова_ходу=слова)
    п = р["паспорт"]
    сц = СЦ.з_показу({}, п)[0]
    типова = (п.get("джерело_полів") or {}).get("нагода") == ПН.ТИПОВА_НАГОДА_РЕЧІ
    ве = РФ.вердикт(спідниця, F, T, сц, типова_нагода=типова)
    print("\n%s → нагода=%s місце=%s ошатність=%s (джерело %s) обовʼязкове=%s"
          % (підпис, п.get("нагода"), п.get("місце"), п.get("ошатність"),
             (п.get("джерело_полів") or {}).get("ошатність") or "—", р["обовʼязкове"]))
    print("   суд спідниці: рівень «%s» · «ошатніша за нагоду»: %s · «Нагоди ти не назвала»: %s"
          % (ве["рівень"], "ошатн" in ве["рядок"], "не назвала" in ве["рядок"]))
