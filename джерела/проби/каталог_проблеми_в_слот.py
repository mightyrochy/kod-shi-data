# -*- coding: utf-8 -*-
# Реєстр проблем бази одягу, напрям В, клас «слот і тип речі». ФАКТ: (1) речей, чий
# предмет у голові назви — інший слот, ніж поставив фід (без поділу «прикраси» на сережки,
# каблучки…, бо це уточнення, не помилка); (2) комплектів (костюм/комплект/двійка) і в якому
# слоті вони лежать; (3) `param тип` — нема / грубий (не з переліку item_type) / з переліку.
import os, re, sys, collections as C
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed, фід_слот as ФС, внутрішня_мова as ВМ
оф = feed.читати_yml(sys.argv[1] if len(sys.argv) > 1 else feed.каталог_на_диску())[0]
слот = {o["id"]: feed.слот(o) for o in оф}
ПРИКРАСИ = {"прикраси", "сережки", "каблучка", "браслет", "намисто", "кольє", "брошка"}
НАБІР = re.compile(r"\b(костюм\w*|комплект\w*|двійк\w*|трійк\w*)\b", re.I)
розб = C.Counter()
for o in оф:
    п = ФС.предмет_назви(ФС.назва_суду(o).lower())
    if not п or п[0] == слот[o["id"]] or {п[0], слот[o["id"]]} <= ПРИКРАСИ:
        continue
    розб["набір" if НАБІР.search(o["назва"]) else (слот[o["id"]], п[0])] += 1
print("оферів у чистому каталозі: %d · без слота: %d"
      % (len(оф), sum(1 for с in слот.values() if not с)))
print("предмет назви ≠ слот фіду: %d, з них комплектів %d; решта: %s"
      % (sum(розб.values()), розб["набір"], dict((k, v) for k, v in розб.most_common(6) if k != "набір")))
наб = [o for o in оф if НАБІР.search(o["назва"])]
print("комплектів за назвою: %d · у слотах: %s"
      % (len(наб), dict(C.Counter(слот[o["id"]] for o in наб).most_common())))
типи = set(ВМ.ТАБЛИЦЯ["item_type"].values())
т = C.Counter("нема" if not (o.get("параметри") or {}).get("тип") else
              ("з переліку" if (o["параметри"]["тип"]) in типи else "грубий") for o in оф)
груб = C.Counter(o["параметри"]["тип"] for o in оф
                 if (o.get("параметри") or {}).get("тип") and o["параметри"]["тип"] not in типи)
print("param тип: %s · грубі: %s" % (dict(т), dict(груб.most_common(8))))
