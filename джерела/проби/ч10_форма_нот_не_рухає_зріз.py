"""Ч-10 доробка (рядок 223): ФОРМА НОТИ СЛОТА НЕ РУХАЄ ЗРІЗ ПУЛУ.

Перевірка #451 дала НІ: словник кодів заяв видовжив промпт, стеля пулу впала K=368→366,
квоти слотів зсунулись — і рука 2 на сіді 4 показала жінці інший верх і інший пояс
(ціна картки −47 000 ₴). Причина: зріз міряв ВЕСЬ промпт, тож нота платила речами пулу.
Тепер вага блоку ноти має власний резерв (`міст_пакет.РЕЗЕРВ_НОТИ_СЛОТІВ`), і проба це
МІРЯЄ, а не обіцяє: те саме дерево прогоняється з чинними визначеннями заяв і з
видовженими — нота важить більше, форма й зміст ті самі. Мусить бути: доки нота в
резерві, K те саме й склад пулу побайтово той самий; за резервом надлишок платять речі,
як доти, і це видно числом, а не мовчанням.
Запуск із `джерела`: PYTHONPATH=. python3 проби/ч10_форма_нот_не_рухає_зріз.py"""
import hashlib, json, os, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent)); os.chdir(sys.path[0])
import bridge as B, feed as F, внутрішня_мова as ВМ, міст_пакет as МП
вх0 = dict(json.load(open("стенд_вх.json", encoding="utf-8")),
           каталог=F.каталог_на_диску("каталог_повний.xml"))
ВСІ = dict(ВМ.ЗАЯВИ)
відпис = lambda п: hashlib.md5(json.dumps(sorted(
    r.get("id") for сл in (п or {}).values() for r in сл), ensure_ascii=False).encode()).hexdigest()[:12]


def прогін(сід, набивка):
    """Пакет руки 1 на цьому сіді, коли кожне визначення заяви довше на `набивка` символів."""
    ВМ.ЗАЯВИ.clear(); ВМ.ЗАЯВИ.update({к: (v + " " + "x" * набивка) if (isinstance(v, str) and набивка) else v
                                       for к, v in ВСІ.items()})
    МП._КЕШ_ПАКЕТА.clear()      # пакет кешується ключем входів, а словник заяв у ключі не стоїть
    вих = json.loads(B.виклик("запити", json.dumps(dict(вх0, сід=сід), ensure_ascii=False)))
    ст = вих.get("стеля") or {}
    return ст.get("вага_ноти"), ст.get("K"), відпис(вих.get("кандидати")), ст.get("символів")


зсувів_у_резерві = 0
for сід in (3, 4):
    (н0, K0, від0, с0) = прогін(сід, 0)
    for набивка, межа in ((500, "у резерві"), (700, "ЗА резервом")):
        н, K, від, с = прогін(сід, набивка)
        зсувів_у_резерві += (межа == "у резерві") and (K != K0 or від != від0)
        print("сід %s · нота %5d → %5d симв. (%-11s резерв %d) · K %s → %s · склад пулу %s → %s · запит %d"
              % (сід, н0, н, межа, МП.РЕЗЕРВ_НОТИ_СЛОТІВ, K0, K, від0, від, с))
прогін(3, 0)
print("ЗСУВІВ ЗРІЗУ ВІД ДОВЖИНИ НОТИ В МЕЖАХ РЕЗЕРВУ: %d (мусить 0) · бюджет %d + резерв %d = "
      "оголошена стеля запиту %d симв."
      % (зсувів_у_резерві, МП._БЮДЖЕТ_СИМВОЛІВ, МП.РЕЗЕРВ_НОТИ_СЛОТІВ,
         МП._БЮДЖЕТ_СИМВОЛІВ + МП.РЕЗЕРВ_НОТИ_СЛОТІВ))
