"""Рядок 43 БЕКЛОГ (рішення власника 19.09: вужчі зони, більше кольорів):
що звуження `verify.ЛЕКСИКОН` зробило з ДВОМА його роботами — підписом чипа
(`palettes._назва`: скільком чипам ґратки слово підписано «найближче», тобто
поза будь-яким вікном) і судом кольору РЕЧЕЙ (`verify.перевірити` на
`каталог_збагачення.json.gz`). Запуск із теки `джерела`:
`PYTHONPATH=. python3 проби/leksykon_zony.py`."""
import sys, pathlib, json, gzip
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import verify as V, palettes as PS, colorspace as cs, bridge as B

осн, порядок = B._ґратка_основ()
найближче = [k for k in порядок if PS._назва(cs.hx(осн[k][0]))[1] == "найближче"]
print("слів у лексиконі: %d · сімей: %d" % (len(V.ЛЕКСИКОН), len(V.СІМ_Ї_СЛІВ)))
print("чипів ґратки: %d · підписано словом ПОЗА його вікном: %d %s"
      % (len(порядок), len(найближче), найближче or ""))

with gzip.open("каталог_збагачення.json.gz", "rt", encoding="utf-8") as f:
    КАТ = json.load(f)
разом = відкинуто = сусід = 0
хто, сусіди = {}, {}
for зб in КАТ.values():
    к = (зб or {}).get("колір_основний") or {}
    слово, hex_ = к.get("слово"), к.get("hex")
    if not слово or not hex_ or слово not in V.ЛЕКСИКОН:
        continue
    разом += 1
    в = V.перевірити(V.hx(hex_), назва=слово)
    if в["вердикт"] == "відкинуто":
        відкинуто += 1
        хто[слово] = хто.get(слово, 0) + 1
    elif в.get("сусід_сім_ї"):
        сусід += 1
        пара = "%s→%s" % (слово, в["сусід_сім_ї"])
        сусіди[пара] = сусіди.get(пара, 0) + 1
print("речей зі словом лексикону й hex: %d" % разом)
print("  вимір відкинуто (суперечить слову й жодному сусідові сім'ї): %d (%.1f %%)"
      % (відкинуто, 100.0 * відкинуто / max(1, разом)))
print("  вимір ЗБЕРЕЖЕНО сусідом тієї ж сім'ї: %d · топ-5 пар: %s"
      % (сусід, sorted(сусіди.items(), key=lambda kv: -kv[1])[:5]))
print("  топ-5 слів, де вимір усе одно суперечить: %s"
      % sorted(хто.items(), key=lambda kv: -kv[1])[:5])
