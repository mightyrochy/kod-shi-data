ВИГАДКИ = [  # (сцена, seed3_N, вигадане в англійському тексті, річ-джерело, що на її кадрі крамниці)
    ("07_ж2_новорічна_мороз", 21, "white top, black pants", "#96·31", "піджак на манекені з білим топом і чорними штанами"),
    ("07_ж2_новорічна_мороз", 21, "black turtleneck, black tights, heeled boots", "#371·01", "пальто на моделі"),
    ("07_ж2_новорічна_мороз", 21, "«Not included in this outfit selection»", "#202·11", "костюм: піджак + палаццо"),
    ("08_ж2_спорт_коментар", 21, "cream sweater tied at the waist, beige trousers", "#204·18", "пояс на светрі"),
    ("08_ж2_спорт_коментар", 21, "chocolate-brown blazer (без палаццо)", "#230·12", "костюм: піджак + палаццо"),
    ("08_ж2_спорт_коментар", 44, "silk scarf at your neck", "#25·09", "блуза на моделі в шовковій хустці")]
шл = feed.каталог_на_диску(); вх = json.load(open("стенд_вх.json", encoding="utf-8"))
за_назвою = {(r.get("назва_показу") or r["назва"], r["id"].split("@")[-1]): r["id"]
             for r in ФК._прочитати_каталог(шл, ліміт_фото=0)["каталог"]}
def записаний(сцена, с):
    т = subprocess.run(["git", "show", "origin/claude/zhyvi-22:../аудит/живі_22/А/%s/VIDPOVIDI/seed3_%d_ОПИС_V1_ОПИС_ВІДПОВІДЬ_V1.txt"
                        % (сцена, с)], capture_output=True, text=True, check=True).stdout.split("── ВІДПОВІДЬ")[0]
    return json.JSONDecoder().raw_decode(т[т.index('{"version"'):])[0]["outfit"]["items"]
рід, кеш, позначено = (lambda x: "/".join(str(x[к]) for к in ("kind", "type") if x.get(к))), {}, [0, 0]
for сцена, с, що, n, кадр in ВИГАДКИ:
    if (сцена, с) not in кеш:
        до = записаний(сцена, с)
        ід = {x["n"]: за_назвою.get((x["name"], x["shop"])) for x in до}
        assert all(ід.values()), ід
        о = json.loads(МО.опис(dict(вх, каталог=шл, номери={v: k for k, v in ід.items()},
                                   речі=[dict(id=ід[x["n"]], слот=ВМ.ТАБЛИЦЯ["slot"].get(x["kind"])) for x in до])))
        кеш[(сцена, с)] = ({x["n"]: x for x in до}, {x["n"]: x for x in json.loads(о["промпт"])["outfit"]["items"]}, о["підписи"])
    до, після, підписи = кеш[(сцена, с)]
    п, п_до = [підписи[N - 1] for N in після[n].get("photos") or ()], ["Photo %d" % N for N in до[n].get("photos") or ()]
    for і, пп in enumerate((п_до, п)): позначено[і] += bool(пп) and all("not in her outfit" in x for x in пп)
    print("── %s seed3_%d · «%s» ← кадр %s (%s)" % (сцена[:2], с, що, n, кадр))
    print("   ДО    рід %-14s підпис кадру: «%s:»\n   ПІСЛЯ рід %-14s підпис кадру: «%s:»"
          % (рід(до[n]), п_до[0], рід(після[n]), п[0] if п else "—"))
print("джерел вигаданого, позначених «кадр крамниці, решта одягу не її»: ДО %d з %d · ПІСЛЯ %d з %d"
      % (позначено[0], len(ВИГАДКИ), позначено[1], len(ВИГАДКИ)))
