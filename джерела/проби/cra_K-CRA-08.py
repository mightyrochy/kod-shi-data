# -*- coding: utf-8 -*-
"""K-CRA-08 (дозування тренду) — «БЕЗ ВХОДУ», сказане вголос:
`python3 проби/cra_K-CRA-08.py`.

Правило просить ОДНОГО входу: позначки, що річ — поточний сезонний хід. Жодне поле
фіду її не несе, і вигадувати її нема з чого: списку сезонних ходів у системі нема,
а сам корпус позначає цей клас найвищою волатильністю (K-SYS-07). Тому емітента
НЕМА навмисно, а пункт 14 чекліста надлишку стоїть у стані «без входу» — і це видно
у вердикті, а не тільки в коді.
ОКРЕМО ПЕРЕВІРЯЄТЬСЯ ОМОНІМ: поле `тренд` у системі вже є — у `silhouette.літера`
воно значить літеру силуету. Предикат чекліста більше не питає його, інакше пункт
мовчки став би «пройдено» через чуже поле."""
import sys, pathlib, json
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B
import суд_образу as СУД, status as СТ

пункт = next(p for p in СУД.ЧЕКЛІСТ_НАДЛИШКУ if p[2] == ("K-CRA-08",))
print("пункт %d: «%s» · вхід, якого бракує: «%s»" % (пункт[0], пункт[1], пункт[3]))
assert пункт[3] != "тренд", "ключ входу знову омонім літери силуету"
обм = next((з for з in СТ.ОБМЕЖЕННЯ if з["id"] == "тренд"), None)
print("у реєстрі обмежень:", (обм or {}).get("що", "НЕМА")[:96])
assert обм, "«без входу» мусить бути записане там, де всі інші межі системи"

вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["гілка"] = 0
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
пул = json.loads(r["руки"]["1"])["пул"]
взяті, речі = set(), []
for слот in ("верх", "низ", "взуття", "шарф"):
    for к in (пул.get(слот) or []):
        if к["н"] not in взяті:            # одна річ не може стояти у двох слотах
            взяті.add(к["н"]); речі.append(к["н"]); break
вд = json.loads(B.виклик("від_моделі", json.dumps(dict(
    вх, текст_моделі=json.dumps({"версія": "1", "образи": [
        {"ід": "о1", "речі": речі}]}, ensure_ascii=False)), ensure_ascii=False)))
о = ((вд.get("вердикт") or {}).get("образи") or [{}])[0]
ч = (о.get("чекліст") or {}).get("надлишок") or {}
print("образ:", речі)
print("чекліст надлишку: провалів %d · пройдено %d · БЕЗ ВХОДУ %d"
      % (len(ч.get("провал") or []), ч.get("пройдено", 0), ч.get("без_входу", 0)))
print("K-CRA-08: емітента нема навмисно — «без входу» ≠ «пройдено», і це у вердикті")
assert ч.get("без_входу", 0) >= 1, ч
