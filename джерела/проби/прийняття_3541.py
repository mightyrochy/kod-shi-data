"""3541: запис ЖИВІ-13 А/08 → два явні прийняття; це контрфактичний розбір, не нова відповідь моделі.
Запуск з джерела доказів: cd джерела && python3 проби/прийняття_3541.py /шлях/джерело_3541.json"""
import copy, json, os, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import повнота_образу as П, розбір_відповідей as Р, дріт_моделі as Д, протокол as К
ф = json.load(open(sys.argv[1], encoding="utf-8")); о = next(x for x in ф["образи"] if x["номер"] == "о3")
база = "9f3523d62319225eabb2c1a2cd382053a4651384"; старі = []
for модуль in ("повнота_образу", "дріт_моделі"):
    простір = {"__name__": модуль + "_до"}
    exec(subprocess.check_output(["git", "show", база + ":джерела/" + модуль + ".py"], text=True), простір)
    старі.append(простір)
ном = dict(zip(о["речі_н"], о["ід"])); каталог = [dict(id=i, **r) for i, r in ф["довідник"].items()]
зн = [dict(z, речі=[ном.get(i, i) for i in z["речі"]]) for z in о["знахідки"]]
образ = dict(ід="о3", речі=о["ід"], знахідки=зн, структура=dict(ок=True, блокери=[]))
вердикт = dict(образи=[образ]); початковий = copy.deepcopy(вердикт)
for ід in ("з-о3-1", "з-о3-12"):
    текст = json.dumps(dict(version="1", chosen="o3", accept=[dict(finding=К.ід_на_дріт(ід), why="Свідомо лишаю цей хід заради задуму.")]))
    результати = []
    for розбір in (старі[0]["вибір_з_json"], П.вибір_з_json):
        вибір = розбір(текст, вердикт, каталог=каталог)
        суд, звіт = Р._застосувати_свідомі(зн, вибір["розриви"], каталог)
        було, стало = next(z["сила_нп"] for z in зн if z["ід"] == ід), next(z["сила_нп"] for z in суд if z["ід"] == ід)
        assert вибір["обрано"] == "о3" and len(вибір["прийнято"]) == 1 and стало == round(було * .6, 3)
        assert all(z == зн[n] for n, z in enumerate(суд) if z["ід"] != ід)
        результати.append((було, стало))
    print(ід, "ДО → ПІСЛЯ (розбір уже працював):", результати)
for прийнято in ([], [dict(finding="f-o3-1", why=" ")], [dict(finding="f-o1-1", why="Чужий.")], [dict(finding="f-o3-999", why="Немає.")]):
    вибір = П.вибір_з_json(json.dumps(dict(version="1", chosen="o3", why="Задум.", accept=прийнято)), вердикт, каталог=каталог)
    assert not вибір["прийнято"] and not вибір["розриви"]
    assert Р._застосувати_свідомі(зн, вибір["розриви"], каталог)[0] == зн
хід = dict(річ=о["речі_н"][1], чому="Свідомий хід.", правило="K-SHO-08", знахідка="з-о3-999")
дріт = К.вердикт_на_дріт(dict(образи=[dict(ід="о3", речі=о["речі_н"], знахідки=о["знахідки"], свідомі=[хід])]))
до, після = [м(дріт, вибір=True)["verdict"][0]["your_declared"][0] for м in (старі[1]["вердикт"], Д.вердикт)]
assert "finding" not in до and після["finding"] == "f-o3-1"
assert П.ВИБІР.поля_виходу["прийнято[].знахідка"] != старі[0]["ВИБІР"].поля_виходу["прийнято[].знахідка"]
assert вердикт == початковий
print("your_declared:", до, "→", після)
print("16 ID / 17 входжень; чужий / невідомий ID / порожнє why / без accept: сила незмінна.")
print("Промпт ДО: лише gate; ПІСЛЯ: gate або remark. Живе мірило не перевірено.")
