# -*- coding: utf-8 -*-
"""K-ACC-01, 02, 05, 06 — чотири правила, що жили опціями третього каналу.

ДО ПРАВКИ: K-ACC-02 і K-ACC-06 стояли в коді рівно одним рядком таблиці
`МІСЦЕ_НАСЛІДКИ` («талія» → «діють передумови пояса»; «плечі» → «асиметрія»),
тобто ОПЦІЯМИ, які правило називають і не виконують. K-ACC-05 емітента не мав
узагалі — ID згадувався лише як приклад «мертвого за побудовою». K-ACC-01 жив
рядком брифа: інструктував модель до складання й не судив нічого після.
ПІСЛЯ: усі чотири стоять у `вердикт.образи[0].знахідки`."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, колір_образу as КО

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
C = lambda c: (КО.гучність(tuple(c["lab"])).get("C") or 0) if c.get("lab") else 0
сумка = next(c for c in кат if c.get("слот") == "сумка" and c.get("формат") == "великий")
шарф = next(c for c in кат if c.get("слот") == "шарф" and "плечі" in (c.get("місця") or ()) and C(c) < 40)
прикр = next(c for c in кат if c.get("слот") == "прикраси" and C(c) >= 40)
пояс = next(c for c in кат if c.get("слот") == "пояс")
база = [next(c for c in кат if c.get("слот") == сл) for сл in ("сукня", "взуття")]
ід = [c["id"] for c in база + [сумка, шарф, прикр, пояс]]
print("сумок із форматом у пакеті %d · тихих шарфів із місцем «плечі» %d"
      % (sum(1 for c in кат if c.get("слот") == "сумка" and c.get("формат")),
         sum(1 for c in кат if c.get("слот") == "шарф" and "плечі" in (c.get("місця") or ()) and C(c) < 40)))

def суди(тіло_вх):
    о = ((json.loads(B.виклик("від_моделі", json.dumps(dict(тіло_вх, ід=ід), ensure_ascii=False))
          ).get("вердикт") or {}).get("образи") or [{}])[0]
    return {z["правило"]: z for z in (о.get("знахідки") or [])}

# талія цієї людини виражена (WHR 0.75) — K-ACC-02 мовчить, і це ВИКОНАНЕ правило
зн = суди(вх)
for ід_п, підпис in (("K-ACC-01", "прикраса C=%.0f" % C(прикр)),
                     ("K-ACC-05", "сумка формат «%s»" % сумка["формат"]),
                     ("K-ACC-06", "шарф із місцем «плечі», тихий")):
    z = зн.get(ід_п)
    print("%s · %-28s → %s" % (ід_п, підпис,
          "НЕМА" if not z else "%s %.2f · %s" % (z["сила"], z["сила_нп"], z["суть"][:52])))
    assert z, "%s мусить дати рядок вердикту" % ід_п
print("K-ACC-02 · WHR 0.75 (талія виражена) →",
      "нема (передумова виконана)" if "K-ACC-02" not in зн else "Є — а мусило мовчати")
assert "K-ACC-02" not in зн

# та сама пара речей на тілі з невираженою талією (WHR 0.85)
зн2 = суди(dict(вх, обхвати=dict(вх["обхвати"], талія=84)))
z = зн2.get("K-ACC-02")
print("K-ACC-02 · WHR 0.85 (талія не виражена) →",
      "НЕМА" if not z else "%s %.2f · %s" % (z["сила"], z["сила_нп"], z["суть"][:56]))
assert z, "без вираженої талії пояс перестає бути першою третьою річчю"
