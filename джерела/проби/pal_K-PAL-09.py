# -*- coding: utf-8 -*-
"""K-PAL-09 (розміщення) — від сліду до знахідки: чужий колір біля обличчя.

Корпус (тема-2:1855): «кольори палітри біля обличчя; кольори поза палітрою — у
слоти далі від обличчя (низ, взуття)». Джерела: K-COL-08, практики («worst
colours away from the face»), Chevreul R-CHEV-15 — індукція локальна, найсильніша
на лінії контакту. Прийом стояв у `palettes.ПРИЙОМИ` з умовою «завжди», лишав
слід «прийом активний» — і жодного образу не судив.
ПІСЛЯ: `pipeline.палітра_образу` дає знахідку на річ, чий колір поза вікнами
палітри, а приобличчева вага слота ≥ `колір_образу.NEAR_МІН`. Ремонт називає
слоти, куди цей колір законно перенести. K-PAL-14 на тій самій речі не дублює
09: воно НАЗИВАЄ колір найдальшим, 09 каже, ДЕ його нести, і на одній речі
спрацьовує рівно одне.
Запуск із теки `джерела`: `python3 проби/pal_K-PAL-09.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import pipeline as PL, колір_образу as КО

# САМОЗВІТ ПОТРІБЕН ПРОБІ, І ЦЕ ЧАСТИНА ФАКТУ: на неконтрольованому фото вісь тону
# утримується (K-PC-05), `_дуги_сімей` віддає ОБИДВІ температурні версії кожної
# сім'ї, і палітра накриває майже все коло тону — поза нею лишаються хіба крайні
# світлоти. Тобто правило мовчить не тому, що мертве, а тому, що в такої людини
# «чужих» кольорів майже нема. Названий бік звужує сім'ї до однієї версії.
вх, r, кат, спец = ПВ.стенд(гілка=0, намір="statement", самозвіт={"метал": "золото"})
П = спец["палітра_практична"]
# ПОЗА ПАЛІТРОЮ — І ВСЕ: 09 не ділить цю множину з 14. Перша редакція правила
# давала на річ рівно одне з двох, і K-PAL-09 діставав самий залишок (тони поза
# вікнами палітри Й поза найдальшими) — на стенді це порожня множина, тобто
# правило `default`-сили мовчало б на кожному живому вході. Корпус пов'язує їх
# прямо: 14 називає колір найдальшим, 09 каже, куди його подіти.
чужий = lambda L, C, h, _: (not PL._нейтральний_тон(h, C, L)
                            and not PL._у_вікнах(П["вікна"], L, C, h))
біля = next((x for с in ("верх", "сукня", "шарф", "головний_убір")
             for x in [ПВ.взяти(r, кат, с, чужий)] if x), None)
print("приобличчеві ваги слотів: %s" % {с: КО.SLOT_NEAR_FALLBACK[с] for с in ("верх", "низ", "взуття")})
if not біля:
    print("ФАКТ · у пулі цього стенда нема речі поза палітрою й поза найдальшими "
          "біля обличчя — правилу нема про що говорити; це стан пулу, не мовчання коду")
    raise SystemExit(0)
решта = [ПВ.взяти(r, кат, с, lambda *a: True) for с in ("низ", "взуття", "сумка")]
ід = [x["id"] for x in [біля] + решта if x]
print("біля обличчя: %s · L%.0f C%.0f h%.0f" % ((біля["назва"] or "")[:40], *ПВ.lch(кат, біля["id"])))
зн, _ = ПВ.знахідки(вх, ід)
print("ФАКТ · K-PAL-09: %s" % ПВ.рядок(зн, "K-PAL-09"))
z = next((x for x in зн if x.get("правило") == "K-PAL-09"), None)
assert z and z["сила"] == "default" and z["сила_нп"] == 0.5, z
print("       ремонт: %s" % z["ремонт"])
