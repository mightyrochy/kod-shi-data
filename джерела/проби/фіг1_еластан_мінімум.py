"""ФІГ-1, рядок 302: склад (частка еластану) входить в умову тканини гілки «нижче
мінімуму носіння» (K-BOD-02). Друкує ДО (склад не читається — як було) / ПІСЛЯ на кожній
речі каталогу з ≥2 % еластану, вдягненій на одне тіло з дефолтним проміжком слота.
Запуск із теки `джерела`: `python3 проби/фіг1_еластан_мінімум.py`."""
import os, sys, collections
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as ФК, fit as ПС, силует_пропорції as СП, силует_крої as СК

кат = ФК._прочитати_каталог(feed.каталог_на_диску(), ліміт_фото=0)["каталог"]
т = ПС.тіло(164, {"плечі": 92, "груди": 90, "талія": 72, "стегна": 104})
H = т["висоти"]
ПРОМІЖОК = {"верх": ("плечі", "стегна"), "низ": ("талія", "щиколотка"),
            "сукня": ("плечі", "коліно"), "комплект": ("плечі", "щиколотка")}
речі = [r for r in кат if (r.get("еластан_%") or 0) >= СП._ЕЛАСТАН_ПОРІГ and r.get("слот") in ПРОМІЖОК]
підсумок = {"до": collections.Counter(), "після": collections.Counter()}
for r in речі:
    в, н = ПРОМІЖОК[r["слот"]]
    for коли in ("до", "після"):
        річ = dict(id=r["id"], слот=r["слот"], тип=r.get("тип"), крій=r.get("крій"),
                   текстура=r.get("текстура"), рід_тканини_слово=r.get("рід_тканини_слово"),
                   верх_см=H[в], низ_см=H[н], **({"еластан_%": r["еластан_%"]} if коли == "після" else {}))
        for з in СП.зонні_операції(т, СК.обгортка(т, [річ])):
            if "мінімуму" in з["суть"]:
                заявлено = "strong" if "«strong»" in (з.get("стеля_тіру") or "") else з["сила"]
                підсумок[коли][(заявлено, з["сила"], з["регістр"])] += 1
print("речей каталогу з еластаном ≥ %g %%: %d (тіло 164 см, стегна 104)" % (СП._ЕЛАСТАН_ПОРІГ, len(речі)))
for коли in ("до", "після"):
    print("  %-6s знахідок «нижче мінімуму»: %d" % (коли.upper(), sum(підсумок[коли].values())))
    for (зая, сила, рег), n in sorted(підсумок[коли].items()):
        print("      заявлено %-8s → сила %-8s регістр %-8s × %d" % (зая, сила, рег, n))
strong = sum(n for (зая, *_), n in підсумок["після"].items() if зая == "strong")
print("ПІСЛЯ: річ із ≥2 %% еластану дістає strong «нижче мінімуму» — %d разів" % strong)
