"""НАМІР-1 (02.10): чи мовна модель ЧУЄ намір у її словах, а не лише слово «вразити». 10 реплік, де вона хоче виділитися
(statement), + 5 контрольних, де наміру нема чи він протилежний (не statement). Той самий шов, що МОВА-1:
`промпт_розмови` → жива модель → `прийняти_розмову` → `мова`. Друкує намір, цитату, влучно/хибно. Запуск: cd джерела &&
ZHYVA=sonnet python3 проби/намір1_чує.py [номери через кому]; без ZHYVA — лише список реплік."""
import json, os, sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); import мова_спільне as С; М = С.М
ВИПАДКИ = [  # (її слова, очікуваний intent: statement | не statement)
    ("на вечірку до подруги, хочу щоб усі на мене дивились", "statement"),
    ("на день народження, хочеться чогось яскравого, не як завжди", "statement"),
    ("на роботу, але мені набридло сіре, хочу щось нове", "statement"),
    ("на корпоратив, хочу бути зіркою вечора", "statement"),
    ("йду в клуб, щось зухвале, хай запамʼятають", "statement"),
    ("на побачення, не хочу бути як усі", "statement"),
    ("ну звісно, сірою мишкою як завжди, а хотілося б хоч раз блиснути", "statement"),
    ("на випускний доньки, хочу щоб на мене озиралися", "statement"),
    ("на вечерю з колегами, хочу щоб помітили, що я теж є", "statement"),
    ("на концерт, хочу виглядати так, щоб ніхто не пройшов повз", "statement"),
    ("на прогулянку, аби було зручно", "не statement"),
    ("на зустріч, щоб не виділятись", "не statement"),
    ("просто на роботу в понеділок", "не statement"),
    ("до лікаря, щоб на мене не звертали уваги", "не statement"),
    ("на день народження до мами, щось скромне і зручне", "не statement"),
]
номери = [int(х) for х in sys.argv[1].split(",")] if len(sys.argv) > 1 else range(1, 16); підс = {"влучно": 0, "хибно": 0}
for н in номери:
    слова, чекаю = ВИПАДКИ[н - 1]
    if not С.МОДЕЛЬ: print("%2d %s" % (н, слова)); continue
    відп, с = С.модель(М.промпт_розмови({"розмова": {"нове": слова, "історія": []}, "сценарій": {}, "паспорт": {}}))
    р = М.прийняти_розмову(відп); п = json.loads(М.мова({"паспорт_з": р["внутрішня"], "сценарій": {}, "паспорт": {}, "слова_розмови": [слова], "частини": р["частини"]}))["паспорт"]
    нам = п.get("намір") or "-"; є = "statement" if нам == "statement" else "не statement"; оц = "влучно" if є == чекаю else "хибно"; підс[оц] += 1
    print("%2d %-7s очікую %-13s маю %-14s %.0fс | цитата: %s" % (н, оц, чекаю, нам, с, п.get("намір_слова") or "-"))
print("РАЗОМ (%s): %s" % (С.МОДЕЛЬ, " · ".join("%s %d" % кв for кв in підс.items())))
