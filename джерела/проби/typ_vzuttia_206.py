# Рядок 206: тестувальниця бачила в офісі при +18 °C руку 1 з «Уги коричневі» —
# замшеві капці. Правило погоди не мало ЗА ЩО зачепитись: «уги» з одним «г» не
# збігалось із жодним ключем, тип виходив None, а без типу мовчать і формальність,
# і K-WEA-07, і регістр. Скільки взуття без типу й чи заговорила погода.
import sys, os, importlib.util
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import feed, фід_каталог as ФК, фід_слот as НОВ, аксесуари_погода as АП
_сп = importlib.util.spec_from_file_location(
    "до_фід_слот", os.environ.get("DO_FID_SLOT", "/tmp/206/до_фід_слот.py"))
СТАР = importlib.util.module_from_spec(_сп); _сп.loader.exec_module(СТАР)
кат = ФК._прочитати_каталог(feed.каталог_на_диску("каталог_повний.xml"), 0)["каталог"]
взуття = [r for r in кат if r.get("слот") == "взуття"]
оф = lambda r: {"назва": r.get("назва"), "категорія": r.get("категорія"),
                "параметри": r.get("параметри") or {}}
тип = lambda м, r: м._тип_речі_обчислити(оф(r), "взуття")
назва = lambda r: (r.get("назва") or "").lower()
СІМʼЇ = (("уги", "уггі"), ("шльопан", "сандалі"), ("слінгбек", "човники"), ("ковбойк", "чоботи"))
# K-WEA-07 мовчить на речі без типу: саме це й бачила тестувальниця.
знах = lambda м, r, t: len(АП.сезон_і_погода(
    [dict(слот="взуття", тип=тип(м, r), назва=r.get("назва"))], темп_c=t, опади="ні"))
без = lambda м: sum(1 for r in взуття if тип(м, r) is None)
print("взуття %d · без типу %d → %d" % (len(взуття), без(СТАР), без(НОВ)))
впало = 0
for ключ, очік in СІМʼЇ:
    # Не «усі дістали ОЧІКУВАНИЙ тип», а «жодна не лишилась без типу»: голова
    # складеного слова законно перемагає («Балетки-слінгбеки» — балетки,
    # «Ботильйони ковбойки» — черевики, правило рядка 184).
    гр = [r for r in взуття if ключ in назва(r)]
    доб = sum(1 for r in гр if тип(СТАР, r) is None)
    сіро = sum(1 for r in гр if тип(НОВ, r) is None)
    впало += сіро
    print("  «%s» n=%-3d без типу %d → %d · очікуваний тип «%s» у %d"
          % (ключ, len(гр), доб, сіро, очік, sum(1 for r in гр if тип(НОВ, r) == очік)))
уги = [r for r in взуття if "уги" in назва(r)]
до18 = sum(знах(СТАР, r, 18) for r in уги)
після18 = sum(знах(НОВ, r, 18) for r in уги)
print("K-WEA-07 на уги при +18 °C: %d → %d знахідок" % (до18, після18))
впало += після18 == 0 or до18 != 0
print("ВПАЛО %d" % впало)
