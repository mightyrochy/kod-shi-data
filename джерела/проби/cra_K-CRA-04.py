"""K-CRA-04 (крок редагування) доходить до виходу суду; знахідка припуску без поля — ні (дошка 12142):
`python3 проби/cra_K-CRA-04.py` (з `джерела/`, каталог розпаковано).

ДОТИ. `status.ВИМКНЕНІ_ПРАВИЛА` знімав K-CRA-04 з причиною правила припуску («фід не несе поля
припуску від виміру речі»), а під цим ід у корпусі — крок редагування (тема-4: «remove any element
whose removal does not reduce any metric»), що поля припуску не читає. І другий обрив, якого за
вимкненням не було видно: `композитор_оцінка.оцінити` не бере `композиція.крок_редагування` у `зн`,
тож знахідка не доходила до вердикту навіть без фільтра (стенд 01.11: 3 спрацювання в `слід_правил`,
у вердикті 0). Стара проба стверджувала «у вердикті НЕМА» — і була зелена з обох причин.

ТЕПЕР. Обидві половини живого мірила на тому самому шляху `bridge.від_моделі`:
  1) образ сукня+взуття+сумка+шарф+пояс: K-CRA-04 спрацьовує й стоїть у знахідках вердикту;
  2) образ із верхнім шаром: K-OUT-06 (драбина припусків) без `припуск_см` — у питаннях (`питання` виходу),
     у знахідках вердикту його нема (регістр «питання», вага 0.0 — `_питання_або_нуль`).
Правил, чия знахідка потребує припуску від виміру речі, у корпусі три (K-OUT-06, K-OUT-07, K-OUT-47),
емітує з них лише K-OUT-06 — тому вимкнення нікуди не перенесено, реєстр порожній."""
import sys, pathlib, json
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B, pipeline as PL, status as СТ

print("реєстр вимкнень:", dict(СТ.ВИМКНЕНІ_ПРАВИЛА) or "порожній")
вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = list(B.каталог_останнього_пакета())


def суд(слоти):
    ід = [next(c["id"] for c in кат if c["слот"] == сл) for сл in слоти]
    вд = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
    о = ((вд.get("вердикт") or {}).get("образи") or [{}])[0]
    return вд, [z["правило"] for z in (о.get("знахідки") or [])]


вд, ред_у_вердикті = суд(("сукня", "взуття", "сумка", "шарф", "пояс"))
спрацювало = [з for з in (вд.get("слід_правил") or [])
              if з.get("правило") == "K-CRA-04" and з.get("ярлик") == "finding_fired"]
print("1) K-CRA-04: спрацювань %d · у вердикті %d" % (len(спрацювало), ред_у_вердикті.count("K-CRA-04")))
вд, пр_у_вердикті = суд(("сукня", "взуття", "сумка", "верхній_шар"))
у_питаннях = [z for z in (вд.get("питання") or []) if z.get("правило") == "K-OUT-06"]
print("2) K-OUT-06 без припуск_см: у питаннях %d · у вердикті %d"
      % (len(у_питаннях), пр_у_вердикті.count("K-OUT-06")))

assert all(str(п).strip() for п in СТ.ВИМКНЕНІ_ПРАВИЛА.values()), "вимкнення без причини"
assert not PL._вимкнене(dict(правило="K-BOD-02", суть="припуск носіння")), \
    "фільтр знову ріже за словом, а не за ID"
assert not PL._вимкнене(dict(правило="K-CRA-04", суть="зайва річ")), "фільтр ріже K-CRA-04"
assert спрацювало, "емітент мовчить — проба нічого не міряє"
assert "K-CRA-04" in ред_у_вердикті, ред_у_вердикті
assert у_питаннях, "драбина припусків не емітувала — друга половина нічого не міряє"
assert "K-OUT-06" not in пр_у_вердикті, пр_у_вердикті
print("ЗЕЛЕНЕ: крок редагування доходить до виходу суду, припуск без поля — ні")
