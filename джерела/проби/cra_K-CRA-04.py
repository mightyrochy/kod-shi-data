# -*- coding: utf-8 -*-
"""K-CRA-04 (крок редагування) — перевірка цілого, а не правка:
`python3 проби/cra_K-CRA-04.py`.

Зведення аудиту ставить правилу «ціле», і воно справді ціле: `суд_образу.крок_
редагування` кличеться з `pipeline.перевірити_образ` і віддає рядки в
`композиція.крок_редагування`. До МОДЕЛІ воно не доходить, і це РІШЕННЯ ВЛАСНИКА
від 05.09.2026, записане іменно й із причиною в `status.ВИМКНЕНІ_ПРАВИЛА`, а не
мовчазна дірка: `pipeline._вимкнене` ріже правило за ID, не за словом у тексті.
Проба стверджує обидві половини: емітент говорить, вимкнення діє й називає себе."""
import sys, pathlib, json
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B, pipeline as PL, status as СТ

причина = СТ.ВИМКНЕНІ_ПРАВИЛА.get("K-CRA-04")
print("вимкнено власником:", (причина or "НІ")[:96])
assert причина, "рішення власника мусить бути записане, а не пам'ятатись рукою"
assert PL._вимкнене(dict(правило="K-CRA-04", суть="будь-який текст")), "фільтр не тримає"
assert not PL._вимкнене(dict(правило="K-BOD-02", суть="припуск носіння")), \
    "фільтр знову ріже за словом, а не за ID"
print("фільтр іменний: K-CRA-04 ріжеться, K-BOD-02 з тим самим словом — ні")

вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
ід = [next(c["id"] for c in кат.values() if c["слот"] == сл)
      for сл in ("сукня", "взуття", "сумка", "шарф", "пояс")]
вд = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
о = ((вд.get("вердикт") or {}).get("образи") or [{}])[0]
у_вердикті = [z for z in (о.get("знахідки") or []) if z["правило"] == "K-CRA-04"]
print("образ із %d речей · K-CRA-04 у вердикті: %s"
      % (len(ід), "НЕМА — саме так" if not у_вердикті else у_вердикті))
assert not у_вердикті, у_вердикті
print("K-CRA-04 ціле: емітент живий, шлях до вердикту закритий рішенням власника")
