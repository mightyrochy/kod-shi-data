# -*- coding: utf-8 -*-
"""Т-19 (прохід 25.09, сід 3): слабка модель кладе `null` у свої списки. Друкує ФАКТИ:
що з такого паспорта прочитав код, чи лишилось «None»/«none» у тексті для жінки й що
це робить із пулом на ПОВНОМУ каталозі. Та сама проба на main дає «до».
Запуск: cd джерела && python3 проби/null_у_списках_т19.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import паспорт_нагоди as ПН, міст_вхід as МВ, profile as PR, feed as Ф

СЦ = dict(нагода="робота", місце="офіс_креативний", година=11, темп_c=18)
З_NULL = {"бажання": [None], "настрій": [None], "питання_людині": [None], "ошатність": [None, 7],
          "невідомо": [None, ""], "вето": {"кольори": ["темні", None], "типи": [None]}}
БЕЗ_NULL = {"вето": {"кольори": ["темні"]}}

def прогін(ім, об):
    п = ПН.паспорт_з_json(json.dumps(об, ensure_ascii=False), СЦ, "не хочу темні")
    д = МВ._застосувати_паспорт(dict(сценарій=dict(СЦ), паспорт=п))
    текст = " | ".join([ПН.паспорт_рядком_людині(п), д["вимоги"], "; ".join(п["питання_людині"]),
                        "хочеш: " + "; ".join(п["бажання"]), "настрій: " + ", ".join(п["настрій"])])
    print("%-9s паспорт: бажання %s · настрій %s · питання %s · вето.кольори %s · вето.типи %s · ошатність %s"
          % (ім, п["бажання"], п["настрій"], п["питання_людині"], п["вето"]["кольори"],
             п["вето"]["типи"], п["ошатність"]))
    print("%-9s жорстке_ні %s · «None»/«none» у тексті для жінки: %s"
          % ("", д["жорстке_ні"], [с for с in ("None", "none") if с in текст] or "нема"))
    return п, д

п1, д1 = прогін("з null:", З_NULL)
п2, д2 = прогін("без null:", БЕЗ_NULL)

# ── ПУЛ НА ПОВНОМУ КАТАЛОЗІ: абсолютний фільтр — те саме місце, де зникало 98 % ──
кат = Ф.прогін(Ф.каталог_на_диску(), [], ліміт_фото=0)["каталог"]
н1 = len(PR.жорстке_ні_фільтр(кат, д1["жорстке_ні"])[0])
н2 = len(PR.жорстке_ні_фільтр(кат, д2["жорстке_ні"])[0])
print("каталог %d речей → після жорсткого «ні»: з null %d · без null %d · порожнє слово межі лишає %d"
      % (len(кат), н1, н2, len(PR.жорстке_ні_фільтр(кат, [""])[0])))
# звірки — ОСТАННІМИ, щоб на main проба надрукувала «до» цілим, а не впала на півдорозі
assert not [с for с in ("None", "none") if с in " ".join(map(str, д1["жорстке_ні"] or []))], д1["жорстке_ні"]
assert д1["жорстке_ні"] == д2["жорстке_ні"], (д1["жорстке_ні"], д2["жорстке_ні"])
assert н1 == н2 == len(PR.жорстке_ні_фільтр(кат, ["темні"])[0]), (н1, н2)
print("ФАКТ: `null` у списках моделі більше не існує після розбору — ні в тексті, ні в межах пулу")
