"""Стани входу й `ok` через конструктор: нуль ваги, без заборони та слів про впевненість."""
import itertools
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from реєстр_правил import зн


def мірило():
    """Звіряє стани проти гейтів, реплік, різних тірів і переданого виміру."""
    випадків = 0
    for правило, стан, тір, вимір in itertools.product(
            ("K-COL-01", "K-COL-05", "K-COL-06", "K-CLR-02", "K-COMP-01",
             "K-ACC-10", "K-KOH-02", "K-PAL-03", "K-PC-05"),
            ("ok", "питання", "утримано"), ("T1", "T3"), (None, 20.0)):
        з = зн(правило, стан, "стан входу", ["річ"], "без числового висновку",
               вимір=вимір, поріг=1.0,
               reg={"поріг": dict(val=1.0, t=тір, прав=[правило])})
        assert з["сила"] == стан and з["сила_нп"] == 0.0 and not з["блокує"], з
        assert not ({"впевненість", "для_стиліста"} & з.keys()), з
        assert з["регістр"] == ("питання" if стан == "питання" else "репліка"), з
        випадків += 1
    print("ФАКТ · станів через конструктор %d · вага 0, заборон і впевненості 0" % випадків)


if __name__ == "__main__":
    мірило()
