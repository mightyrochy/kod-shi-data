# -*- coding: utf-8 -*-
"""Промпт ремонту й ремонту повноти рук 1–2 до/після П-2 на сирих прогонах ноутбука (ВЕРДИКТ_V1 → ОБРАЗИ_V1).

Той самий вердикт на дроті (старий промпт без `завдання`; вердикт до Т-7 — крізь
`міст_відповіді._вердикт_для_моделі`) крізь `дріт_моделі.вердикт` і оголошення `РЕМОНТ` чи
`ПОВНОТА` (промпт «жоден образ не можна показати»): символи й токени gemma (GEMMA_TOKENIZER)
старого й нового, загублені факти даних і факти, що доти стояли реченнями вимог: неповні
образи (образ → блокер у його «structure») і слот розриву («break_kind»).
Запуск: cd джерела && GEMMA_TOKENIZER=… python3 проби/промпт_ремонту.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import дріт_факти as Ф, дріт_моделі as Д, збирач_промптів as ЗП, вердикт_моделі as В, повнота_образу as ПО
import міст_відповіді as МВ, протокол as П
разом = [0, 0, 0]
for ім, п in Ф.сирі("*ВЕРДИКТ_V1_ОБРАЗИ_V1*"):
    ст = json.loads(п); з = ст["завдання"]; повнота = з["вимоги"][0].startswith("ЖОДЕН")
    дріт = {к: v for к, v in ст.items() if к != "завдання"}
    дріт = (МВ._вердикт_для_моделі(дріт) if "образи" in дріт   # вердикт до Т-7; «бракує» чекліста — як на main
            else dict(дріт, вердикт=[dict(с, чекліст=П._чекліст_на_дріт(с.get("чекліст"))) for с in дріт["вердикт"]]))
    пари, розрив = Ф.вимоги_даними(з["вимоги"])
    дріт.update(завдання={"образів": з["образів"]}, **({"слот_розриву": розрив} if розрив else {}))
    нв = ЗП.зібрати(ПО.ПОВНОТА if повнота else В.РЕМОНТ, Д.вердикт(Ф.з_осями(дріт), ремонти=not повнота),
                    мова_тексту="English")
    н = json.dumps(нв, ensure_ascii=False, separators=(",", ":"))
    бл = {о["your_outfit"].get("id"): {б.get("code") for б in (о.get("structure") or {}).get("blockers") or []}
          for о in нв["verdict"]}
    без = (Ф.загублено(ст, н) + ["%s: %s" % (і, к) for і, к in пари if Д._БЛОКЕР[к] not in бл.get(і, ())]
           + ([розрив] if розрив and нв.get("break_kind") != Д.код("slot", розрив) else []))
    разом[0] += 1; разом[1] += len(без); разом[2] += len(пари) + bool(розрив)
    print("%-44s %-7s було %6d симв / %5s ток → стало %6d симв / %5s ток · з речень вимог полями %2d · загублено: %s"
          % (ім[:44], "повнота" if повнота else "ремонт", len(п), Ф.ток(п), len(н), Ф.ток(н),
             len(пари) + bool(розрив), без[:6] or "нічого"))
print("прогонів %d, фактів із речень вимог %d, загублених фактів разом %d" % (разом[0], разом[2], разом[1]))
