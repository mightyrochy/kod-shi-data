# -*- coding: utf-8 -*-
"""Промпт ремонту й ремонту повноти рук 1–2 до/після П-2 на сирих прогонах ноутбука (ВЕРДИКТ_V1 → ОБРАЗИ_V1).

Той самий вердикт на дроті крізь `дріт_моделі.вердикт` і оголошення `РЕМОНТ` чи `ПОВНОТА`
(`дріт_факти.ремонт_з_сирого`): символи й токени gemma (GEMMA_TOKENIZER) старого й нового,
загублені факти даних і факти, що доти стояли реченнями вимог: неповні образи (образ → блокер
у його «structure») і слот розриву («break_kind»).
Запуск: cd джерела && GEMMA_TOKENIZER=… python3 проби/промпт_ремонту.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import дріт_факти as Ф, дріт_моделі as Д
разом = [0, 0, 0]
for ім, п in Ф.сирі("*ВЕРДИКТ_V1_ОБРАЗИ_V1*"):
    нв, повнота, пари, розрив = Ф.ремонт_з_сирого(п)
    н = json.dumps(нв, ensure_ascii=False, separators=(",", ":"))
    бл = {о["your_outfit"].get("id"): {б.get("code") for б in (о.get("structure") or {}).get("blockers") or []}
          for о in нв["verdict"]}
    без = (Ф.загублено(json.loads(п), н) + ["%s: %s" % (і, к) for і, к in пари if Д._БЛОКЕР[к] not in бл.get(і, ())]
           + ([розрив] if розрив and нв.get("break_kind") != Д.код("slot", розрив) else []))
    разом[0] += 1; разом[1] += len(без); разом[2] += len(пари) + bool(розрив)
    print("%-44s %-7s було %6d симв / %5s ток → стало %6d симв / %5s ток · з речень вимог полями %2d · загублено: %s"
          % (ім[:44], "повнота" if повнота else "ремонт", len(п), Ф.ток(п), len(н), Ф.ток(н),
             len(пари) + bool(розрив), без[:6] or "нічого"))
print("прогонів %d, фактів із речень вимог %d, загублених фактів разом %d" % (разом[0], разом[2], разом[1]))
