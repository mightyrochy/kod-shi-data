# -*- coding: utf-8 -*-
"""Рядок 227: виміряний НУЛЬ частки металу (`фід_збагачення.частка_металу`) — два різні твердження.
«Деталь» (обруч із обідком, шкіряний пасок із пряжкою): кадр не бачить металу на поверхні.
«Метал названо хибно» (gepur ж-07619: склад «золото», кадр «срібний 0.56 #bababa»): кадр бачить
метал ІНШОГО тону — слово моделі з металевих (`verify.МЕТАЛИ`) і hex у вікні того металу.
Друкує, скільки нулів якого роду на каталозі руки 1, скільки речей несуть `метал_спір` (R-FEED-01)
і яку причину називає K-COL-06-M (`суд_блиск.метали`). Моделі не кличе.
Запуск: cd джерела && python3 проби/нуль_металу_227.py"""
import collections, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import фід_каталог as ФК, palettes as ПЛ, суд_блиск as СБ                     # noqa: E401,E402
записи = ФК._прочитати_каталог(ФК.каталог_на_диску(), ліміт_фото=0)["каталог"]
нулі = [r for r in записи if r.get("частка_металу") == 0 and r.get("слот") in ПЛ.СЛОТИ_МЕТАЛУ]
спір = [r for r in нулі if r.get("частка_металу_тон_кадру")]
print("нулів частки металу %d · «деталь» %d · «метал названо хибно» %d"
      % (len(нулі), len(нулі) - len(спір), len(спір)))
for r in спір:
    print("   %s %-9s склад «%s», кадр «%s» · %s" % (r["id"][:24], r["слот"], r["метал"],
          r["частка_металу_тон_кадру"], (r.get("назва") or "")[:40]))
print("речей із `метал_спір` (R-FEED-01): %d, з них із боку кадру (нуль металу) %d"
      % (sum(1 for r in записи if r.get("метал_спір")), sum(1 for r in спір if r.get("метал_спір"))))
# ПРИЧИНА В ЗНАХІДЦІ: образ, де єдина металева річ — ж-07619 (кадр сріблястий), проти обруча
for r in [x for x in нулі if x["id"].startswith(("ж-07619", "ж-07665"))]:
    E = [dict(річ=r["id"], метал=r["метал"], слот=r["слот"], near=0.9, площа=0.01, lab=r["lab"],
              частка_металу=0.0, метал_кадру=r.get("частка_металу_тон_кадру"))]
    з = next((z for z in СБ.метали(E, {}) if z.get("правило") == "K-COL-06-M"), {})
    print("K-COL-06-M на %s: %s · заяви %s" % (r["id"][:9], з.get("суть"),
          [x["code"] for x in з.get("заяви") or []]))
