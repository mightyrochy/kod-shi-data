# -*- coding: utf-8 -*-
"""Проба (рядок 1680): B4 і B1 на одній базі — усі різні образи рук 1–2 зі збережених прогонів
(`аудит/перевірки/**/вердикти*.gz`, `ід` кроків; речі — з каталогу через `композитор_річ._у_річ`).
Друкує: стани B4; скільки провалів B4 при речі, чий вхід B4 невідомий (ДО вхід — `текстура`,
ПІСЛЯ — `суд_інтерес.поверхня_речі`: текстура або волокно); провали K-INT-04 (B1) на траурі
(`тихо=True`, сцени «похорон»). Моделі не кличе. Запуск: python3 джерела/проби/прикр2_b4_траур.py"""
import collections, glob, gzip, os, re, sys                                   # noqa: E401
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ)
import фід_каталог as ФК, композитор_річ as КР, outfit as O                    # noqa: E401,E402
import суд_чеклісти as СЧ, суд_інтерес as СІ                                  # noqa: E401,E402
вхід = getattr(СІ, "поверхня_речі", lambda e: e.get("текстура"))
за_ід = {r["id"]: r for r in ФК._прочитати_каталог(ФК.каталог_на_диску(), ліміт_фото=0)["каталог"]}
набори = {}
for ф in sorted(glob.glob(os.path.join(ТУТ, "..", "аудит", "перевірки", "**", "вердикти*.gz"), recursive=True)):
    for м in re.finditer(r'\\?"ід\\?": ?\[([^\]]*)\]', gzip.open(ф).read().decode()):
        ід = tuple(sorted(set(re.findall(r'ж-[^"\\,]+', м.group(1)))))
        if len(ід) >= 2 and all(і in за_ід for і in ід):
            набори.setdefault(ід, "похорон" in ф)
ст, невід, b1 = collections.Counter(), 0, collections.Counter()
for ід, траур in набори.items():
    E = O.елементи([КР._у_річ(за_ід[і], за_ід[і]["слот"], None) for і in ід])
    b4 = next(p for p in СЧ.чеклісти([], E)["прісність"] if p["пункт"] == "B4")
    ст[b4["стан"]] += 1
    невід += b4["стан"] == "провал" and any(not вхід(e) for e in СЧ.одна_на_річ(E))
    if траур:
        b1["провал" if СІ.підлога_інтересу_проактивно(E, "conventional", тихо=True) else "пройдено"] += 1
print("база: образів рук 1–2 %d (траурних %d)" % (len(набори), sum(набори.values())))
print("B4: %s" % dict(ст))
print("B4 провал при речі з невідомим входом B4: %d з %d" % (невід, len(набори)))
print("B1 (K-INT-04, тихо) на траурі: %s" % dict(b1))
