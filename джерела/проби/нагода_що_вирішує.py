"""Що НАСПРАВДІ вирішує кожна нагода зі списку (І-1 28.09, переписано НГ-2 01.10.2026).

Питання власника 28.09: «Яка принципова різниця в образах "робота" "співбесіда" "офіційний
захід", навіщо два різні рядки весілля?». Сценарій — як із показу: плитка + її типове місце
(`показ.html` `чиннеМісце`). Рішення коду — те, що з нагоди доходить до пулу, суду й брифу:
смуга, «надворі», вечір, ліміт відкритих зон K-KOH-10, нота руху про взуття, палітра
(профіль за вимірами, лише робочі межі), траур K-OCC-01, обовʼязкова сумка.
До НГ-2 (main 7112e4f, лише смуга + надворі + палітра): 14 рішень на 18 нагод, 4 пари однакові.
Запуск із теки `джерела`: `python3 проби/нагода_що_вирішує.py`."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import формальність as Ф, паспорт_нагоди as ПН
МЕЖІ = ("вето_майже_біле", "стеля_гучності", "стеля_хроми", "L_макс", "L_вікно")
старе, нове = {}, {}
print("%-14s %-10s %-4s %-4s %-4s %-6s %-5s %-23s %s" % ("нагода", "смуга", "надв", "веч", "зон", "рух", "сумка", "палітра", "межі"))
for к in ПН.ключі_нагоди():
    сц = dict(нагода=к, місце=ПН.типове_місце(к))
    с, о = Ф.сценарій(**сц), ПН.ознаки_нагоди(сц)
    пр = Ф.профіль_палітри(о)
    межі = tuple((м, Ф.НАГОДА[пр][м]) for м in МЕЖІ if пр and Ф.НАГОДА[пр].get(м))
    надв = с["weather_layer"]["перевіряти_стан_надворі"]
    зон = (2 if с["вечір"] else 1) - (1 if с["стримано"] else 0)
    рух = о["рух_під_взуття"] or "—"
    print("%-14s %-10s %-4s %-4s %-4d %-6s %-5s %-23s %s" % (к, с["діапазон"], "так" if надв else "—",
          "так" if с["вечір"] else "—", зон, рух, "так" if о["сумка"] else "ні", пр or "—", ", ".join(м for м, _ in межі) or "—"))
    старе.setdefault((с["діапазон"], надв, межі), []).append(к)
    нове.setdefault((с["діапазон"], надв, межі, с["вечір"], зон, рух, о["сумка"], tuple(с["вето"])), []).append(к)
for ім, гр in (("за старим означенням (смуга, надворі, палітра)", старе), ("за рішенням коду НГ-2", нове)):
    пари = [г for г in гр.values() if len(г) > 1]
    print("\n%s: різних рішень %d на %d нагод, однакових груп %d" % (ім, len(гр), sum(map(len, гр.values())), len(пари)))
    for г in пари: print("  код НЕ розрізняє: %s" % " = ".join(г))
assert not [г for г in нове.values() if len(г) > 1], "НГ-2: однакових рішень лишатись не має"
