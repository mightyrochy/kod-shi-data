"""Що НАСПРАВДІ вирішує кожен рядок списку нагод (НЛ-1, 28.09.2026; власник: «Яка принципова
різниця в образах "робота" "співбесіда" "офіційний захід", навіщо два різні рядки весілля?»).
Друкує на кожен рядок довідника рішення коду — смугу (`сценарій` з нагодою), палітрове правило
`НАГОДА`, «надворі», межу відкритих зон K-KOH-10, рух, обов'язковість сумки й взуття — і слово,
яким нагода їде моделі. Називає рядки з однаковим рішенням. Запуск із `джерела`."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import формальність as Ф, паспорт_нагоди as ПН, внутрішня_мова as ВМ


def правило(ключ):
    оп = Ф.НАГОДА.get(ключ)
    if оп is None:
        return "нема"
    ч = ["вето майже-білого"] if оп.get("вето_майже_біле") else []
    for поле, ім in (("стеля_гучності", "гучність<=%.0f"), ("стеля_хроми", "хрома<=%.0f"), ("L_макс", "L<=%.0f")):
        if оп.get(поле): ч.append(ім % оп[поле])
    if оп.get("L_вікно"): ч.append("L%s" % (оп["L_вікно"],))
    return ", ".join(ч) or "запис без обмежень"


однакові = {}
print("%-14s %-11s %-6s %-5s %-4s %-7s %-14s %s" % ("нагода", "смуга", "надв", "зони", "рух", "сумка", "моделі", "палітра"))
for р in ПН.довідник()["нагоди"]:
    к = р["ключ"]; с = Ф.сценарій(нагода=к)
    надв = с["weather_layer"]["перевіряти_стан_надворі"]
    зони = Ф.ліміт_відкритих_зон({"нагода": к})[0]
    рух = Ф.рух_нагоди({"нагода": к}); сумка = not Ф.без_сумки_й_взуття({"нагода": к})
    слово = ВМ.код("occasion", к) + "".join(" (+%s)" % ВМ.код("occasion", с_) for с_ in р.get("синоніми") or ())
    рішення = (tuple(с["діапазон"]), надв, зони, рух, сумка, правило(к))
    print("%-14s %-11s %-6s %-5s %-4s %-7s %-14s %s" % (к, с["діапазон"], надв, зони, рух, сумка, слово, рішення[-1]))
    однакові.setdefault(рішення, []).append(р["підпис"])
print("\nрядків списку: %d, різних рішень: %d" % (sum(len(v) for v in однакові.values()), len(однакові)))
for сл in (v for v in однакові.values() if len(v) > 1):
    print("  код НЕ розрізняє: %s" % " = ".join(сл))
