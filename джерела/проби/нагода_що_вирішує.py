"""Що НАСПРАВДІ вирішує кожна нагода зі списку (28.09.2026, питання власника:
«Яка принципова різниця в образах "робота" "співбесіда" "офіційний захід",
навіщо два різні рядки весілля?»).

Нагода доходить до образу трьома речами й більше нічим: смуга ошатності
(`МІСЦЯ_ДІАПАЗОНИ` через `НАГОДА_У_МІСЦЕ`), палітрове правило (`НАГОДА`) і
прапорець «надворі». Проба друкує ці три на кожен ключ і називає ті, що
збігаються ПОВНІСТЮ, — тобто рядки, між якими жінці нема чого обирати.

Запуск із теки `джерела`: `python3 проби/нагода_що_вирішує.py`."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import формальність as Ф, паспорт_нагоди as ПН


def правило(ключ):
    оп = Ф.НАГОДА.get(ключ)
    if оп is None:
        return "нема"
    ч = []
    if оп.get("вето_майже_біле"): ч.append("вето майже-білого")
    for поле, ім in (("стеля_гучності", "гучність<=%.0f"), ("стеля_хроми", "хрома<=%.0f"),
                     ("L_макс", "L<=%.0f")):
        if оп.get(поле): ч.append(ім % оп[поле])
    if оп.get("L_вікно"): ч.append("L%s" % (оп["L_вікно"],))
    return ", ".join(ч) or "запис без обмежень"


однакові = {}
print("%-16s %-22s %-11s %-8s %s" % ("нагода", "місце", "смуга", "надворі", "палітрове правило"))
for р in ПН.довідник()["нагоди"]:
    с = Ф.сценарій(місце=р["місце"])
    надворі = с["weather_layer"]["перевіряти_стан_надворі"]
    пр = правило(р["ключ"])
    print("%-16s %-22s %-11s %-8s %s" % (р["ключ"], р["місце"], с["діапазон"], надворі, пр))
    однакові.setdefault((tuple(с["діапазон"]), надворі, пр), []).append(р["підпис"])
пари = [сл for сл in однакові.values() if len(сл) > 1]
print("\nрізних рішень: %d на %d нагод" % (len(однакові), sum(len(с) for с in однакові.values())))
for сл in пари:
    print("  код НЕ розрізняє: %s" % " = ".join(сл))
