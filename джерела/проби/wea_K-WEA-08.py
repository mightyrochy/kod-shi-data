# -*- coding: utf-8 -*-
"""K-WEA-08 (сезон і волога — ворота КОЖНОГО аксесуара): `python3 проби/wea_K-WEA-08.py`.

ЧОМУ БУЛО «БЕЗ СЛІДУ»: правило читало `матеріал_верху or тканина`. Обидва поля —
ВЗУТТЄВІ: `матеріал_верху` пише `feed._взуттєві_поля` лише для слота «взуття»,
ключа `тканина` запис каталогу не має зовсім. А слоти цього правила — головний
убір, шарф, рукавички, сумка. Отже матеріал тут був порожнім рядком на 620 із 620
речей, і ОБИДВІ гілки (літня форма в мороз, зимова в спеку) мовчали за побудовою.
Виміряно після правки: 192 речі цих слотів несуть сезонний матеріал — 113 літніх,
79 зимових.
ЩО ПОКАЗУЄ ПРОБА: шовковий/бавовняний шарф при −8 °C дає рядок про ФУНКЦІЮ (не
гріє), а не вето; при +20 °C того самого рядка нема."""
import sys, pathlib, json
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import feed as Ф, bridge as B, accessory as АК

вх = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml"); вх["гілка"] = 0
вх["сценарій"].update(темп_c=-8, опади="сніг")
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
мат = lambda c: (c.get("матеріал_верху") or c.get("волокно") or c.get("матеріал") or "").lower()
літні = [c for c in кат if c.get("слот") in ("шарф", "головний_убір")
         and АК._літній_матеріал(мат(c))]
print("літніх аксесуарів у слотах шарф/убір:", len(літні), "(до правки поле читалось як порожнє)")
ціль = літні[0]
решта = [next(c["id"] for c in кат if c.get("слот") == сл) for сл in ("сукня", "взуття")]
print("річ:", ціль["назва"][:46], "· слот", ціль["слот"], "· матеріал «%s»" % мат(ціль))
for підпис, t in (("−8 °C", -8), ("+20 °C", 20)):
    вх["сценарій"]["темп_c"] = t
    вм = json.loads(B.виклик("від_моделі", json.dumps(
        dict(вх, ід=[ціль["id"]] + решта), ensure_ascii=False)))
    о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
    з = next((z for z in (о.get("знахідки") or []) if z.get("правило") == "K-WEA-08"), None)
    print("%-8s K-WEA-08:" % підпис, "НЕМА" if not з else
          "%s %.2f · %s" % (з["сила"], з["сила_нп"], з["суть"][:52]))
