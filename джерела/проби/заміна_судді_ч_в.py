# -*- coding: utf-8 -*-
"""Ч-В Е3: суди блиску й формальності не пропонують замін без суду образу з ними.
ДО/ПІСЛЯ: виміри, сила, учасники ті самі; ремонт, ремонт_заяви, запит заміни — нема. Запуск: [SHA бази]."""
import copy, importlib, pathlib, subprocess, sys, types
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import colorspace as cs
БАЗА = sys.argv[1] if len(sys.argv) > 1 else "8f2627cdfd7dd70d7fa3f933e53cdeef0172fb26"
F = cs.features(cs.hx("#e8c4a8"), cs.hx("#3a2a20"), cs.hx("#5a4a30"))
м = lambda і, мет, near=.8, сл="сережки": dict(річ=і, слот=сл, метал=мет, near=near, полірування="глянець", hex="#c8a050", L=60., C=10., площа=.02)
ЕМ = [м("а", "золото"), м("б", "золото", сл="кольє"), м("в", "срібло", сл="браслет"), м("г", "мідь", .3, "каблучка")]
ЕБ = [dict(річ=і, слот=с, блиск=б, L=40., C=5., площа=.2) for і, с, б in
      [("а", "верх", 3), ("б", "низ", 3), ("в", "взуття", 2), ("г", "сумка", 1), ("д", "верхній_шар", 1)]]
ЕФ = [dict(річ="а", слот="верх", формальність=8, площа=.3), dict(річ="б", слот="взуття", формальність=2, площа=.1)]
ВИПАДКИ = [("суд_блиск", "блиск_бюджет", (ЕБ,), {}),
           *[("суд_блиск", "метали", (ЕМ, F), к) for к in ({}, dict(прикраси="без прикрас"), dict(прикраси="перли"),
                                                           dict(прикраси="срібло"))],
           ("суд_блиск", "метали", ([dict(річ="х", слот="верх", L=1.)], F), dict(прикраси="золото")),
           ("формальність", "формальність_образу", (ЕФ, {"діапазон": (7, 9), "risk_posture": "neutral"}), {})]
ПОЛЕ = ("ремонт", "ремонт_заяви", "запит_у_каталог")
if __name__ == "__main__":
    всього = з_порадою = 0
    for мод, ф, арг, кв in ВИПАДКИ:
        до = types.ModuleType(мод)
        exec(subprocess.check_output(["git", "show", БАЗА + ":джерела/" + мод + ".py"]).decode("utf-8"), до.__dict__)
        було = getattr(до, ф)(*copy.deepcopy(арг), **кв); стало = getattr(importlib.import_module(мод), ф)(*copy.deepcopy(арг), **кв)
        було = було[0] if isinstance(було, tuple) else було; стало = стало[0] if isinstance(стало, tuple) else стало
        assert len(було) == len(стало), (ф, кв)
        for а, б in zip(було, стало):
            assert {к: v for к, v in а.items() if к not in ПОЛЕ} == {к: v for к, v in б.items() if к not in ПОЛЕ}, (ф, а["правило"])
            assert not any(б.get(к) for к in ПОЛЕ), (ф, б["правило"]); всього += 1; з_порадою += bool(а.get("ремонт"))
        print(ф, кв, [з["правило"] for з in стало])
    print("Знахідок без неперевіреної поради:", всього, "· мали пораду ДО:", з_порадою)
