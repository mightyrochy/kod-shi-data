# -*- coding: utf-8 -*-
"""Рядок 59 дошки: чи подає плашка-основа ВЕСЬ спектр свого слова.

Друкує факт по кожній рекомендованій плашці: слово, вікно (L*, C*, дуга тону),
обрана вісь із числом ширини й зразки. Плюс лічба: скільки плашок мають вікно
слова ШИРШЕ за клітинку ґратки (градієнт показує лише перетин) і чи лишився
`база_hex` дотику тим самим (центр клітинки — градієнт не обирає точку).
Запуск із теки `джерела`: `python3 проби/плашки_59.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import colorspace as cs
import міст_основи as M

F = cs.features(cs.hx("#f0d5c8"), cs.hx("#3b2c22"), cs.hx("#5b7f86"))
о = M._основи(F)
усі = о["рекомендовані"] + о["інші"]
сім = sorted(о["рекомендовані"], key=lambda x: -x["бал"])[:7]
for x in сім:
    в = x["вікно"]
    print("%-32s %s  %s" % (x["ключ"], x["hex"], в["чому"]))
    print("    L %s  C %s  h %s" % (в["L"], в["C"], в["тон"]))
    print("    зразки %s  (обрізано стелею поверхні: %d)" % (в["зразки"], в["обрізано_стелею"]))
    print("    вікно слова ширше за клітинку по осях: %s" % (в["слово_ширше"] or "—"))

ширші = [x for x in усі if x["вікно"]["слово_ширше"]]
осі = {}
for x in усі:
    осі[x["вікно"]["вісь"]] = осі.get(x["вікно"]["вісь"], 0) + 1
print("\nплашок усього %d; вікно слова ширше за клітинку у %d (осі: %s)"
      % (len(усі), len(ширші),
         ", ".join(sorted({вісь for x in ширші for вісь in x["вікно"]["слово_ширше"]}))))
print("головна вісь: %s" % осі)
print("зразків на плашку: %s" % sorted({len(x["вікно"]["зразки"]) for x in усі}))
print("плашок, де слово дісталось не вікном, а найближчим: %d"
      % sum(1 for x in усі if x["вікно"]["поза_словом"]))
# `база_hex` дотику мусить лишитись ЦЕНТРОМ клітинки, побайтово тим самим.
таб, _ = M._ґратка_основ()
розбіг = [x["ключ"] for x in усі if x["hex"] != таб[x["ключ"]][0]]
print("база_hex дотику = центр клітинки ґратки для всіх %d плашок: %s"
      % (len(усі), "так" if not розбіг else "НІ — %s" % розбіг[:3]))
