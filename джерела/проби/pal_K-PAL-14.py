# -*- coding: utf-8 -*-
"""K-PAL-14 (найдальші кольори) — від сліду до знахідки у вердикті.

Корпус (тема-2:1861): «найдальші» — область з УСІМА осями, оберненими проти
домінанти людини: жодної спільної характеристики з нею. Це не заборона —
K-PAL-08 і K-PAL-09 кажуть, як їх усе ж нести. Код рахував цю область від
початку (`palettes.найдальші`) і клав у `trace`; жоден образ вона не судила, і
рядок «найдальші: глибокі, ясні» доїжджав у бриф як довідка.
ПІСЛЯ: `pipeline.палітра_образу` дає знахідку, коли найдальший колір стоїть БІЛЯ
ОБЛИЧЧЯ (приобличчева вага ≥ `колір_образу.NEAR_МІН`) — бо саме там індукція
локальна (R-CHEV-15), і саме про це місце практики кажуть «worst colours away
from the face». Запуск із теки `джерела`: `python3 проби/pal_K-PAL-14.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import pipeline as PL

вх, r, кат, спец = ПВ.стенд(гілка=0, намір="statement")
П = спец["палітра_практична"]
далекі = П["найдальші"]["вікна"]
print("вікно палітри L %.0f–%.0f C %.0f–%.0f · найдальші «%s»: L %.0f–%.0f C %.0f–%.0f"
      % (П["вікна"]["L"][0], П["вікна"]["L"][1], П["вікна"]["C"][0], П["вікна"]["C"][1],
         П["найдальші"]["словами"], далекі["L"][0], далекі["L"][1], далекі["C"][0], далекі["C"][1]))

# НЕ-НЕЙТРАЛЬ обовʼязково: нейтраль законна під будь-яку схему й під будь-яку
# палітру (K-COL-06), і «найдальшої нейтралі» не буває — камель L*35 C*23 h*63
# лежить у вікнах найдальших і при цьому є теплою нейтраллю.
у_далеких = lambda L, C, h, _: (not PL._нейтральний_тон(h, C, L)
                                and PL._у_вікнах(далекі, L, C, h))
# ЗАПАСНИЙ ХІД — З КАТАЛОГУ (18.09.2026). Після збагачення каталогу (колір речі
# береться з фото, а не зі слова крамниці) пул ЦІЄЇ людини найдальшого кольору
# більше не несе — і це палітра працює, а не правило мовчить. Але судить код не
# пул, а ОБРАЗ: `перевірити_від_моделі` бере річ із каталогу за id і лише ПОЗНАЧАЄ
# її як поза кандидатами. Модель може її назвати, жінка може її вдягнути — і
# правило мусить говорити. Той самий хід, що вже стоїть у K-PAL-03 і K-PAL-07.
біля = next((x for слот in ("верх", "сукня", "шарф")
             for x in [ПВ.взяти(r, кат, слот, у_далеких)
                       or ПВ.з_каталогу(кат, слот, у_далеких)] if x), None)
assert біля, "у каталозі нема жодної не-нейтральної речі у вікнах найдальших"
решта = [ПВ.взяти(r, кат, с, lambda *a: True) for с in ("низ", "взуття", "сумка")]
ід = [x["id"] for x in [біля] + решта if x]
print("біля обличчя: %s · L%.0f C%.0f h%.0f" % ((біля or {}).get("назва", "—")[:44], *ПВ.lch(кат, біля["id"])))
зн, _ = ПВ.знахідки(вх, ід)
print("ФАКТ · K-PAL-14: %s" % ПВ.рядок(зн, "K-PAL-14"))
print("       K-PAL-09 (те саме місце, інше твердження): %s" % ПВ.рядок(зн, "K-PAL-09"))
z = next((x for x in зн if x.get("правило") == "K-PAL-14"), None)
assert z, "найдальший колір біля обличчя не дав знахідки"
assert z["сила"] == "hint" and z["сила_нп"] == 0.2, z          # T3, корпусна сила
assert z.get("регістр") and z.get("ремонт"), z                 # ремонт доїжджає до моделі
print("       ремонт: %s" % z["ремонт"])
