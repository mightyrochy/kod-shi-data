# -*- coding: utf-8 -*-
"""НГ-2б (рядки 243, 400): чи доходить смуга ошатності нагоди до ДОБОРУ речей пулу руки 1.

Пакет руки 1 (`bridge.запити`, каталог_повний, стенд_вх, сід 3) на 8 плитках + співбесіда,
офіційний захід удень, театр, прогулянка. Річ «поза смугою»: її інтервал (`інтервал_формальності`;
без типу — бал фото) не перетинає смугу нагоди; «невідома» — нема ні того, ні того.
Друкує частки, казуальні типи в пулі й пари нагод з однаковими першими речами пулу (=картки стенда).
Запуск: cd джерела && python3 проби/нагода_добір_пулу.py"""
import os, sys, json, collections
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge as B, формальність as Ф, паспорт_нагоди as ПН, фід_каталог as ФК
НАГОДИ = ("щоденне", "робота", "побачення", "свято", "весілля_гість", "траур", "подорож", "спорт",
          "співбесіда", "формал_день", "театр", "прогулянка")
КАЗУАЛЬНІ = ("кеди", "кросівки", "футболка", "берет", "шопер", "сумка_шопер", "худі", "шльопанці", "уги")
СЛОТИ = ("верх", "низ", "сукня", "взуття", "сумка", "головний_убір", "верхній_шар")
картки, вх0 = {}, json.load(open("стенд_вх.json"))
for к in НАГОДИ:
    сц = dict(нагода=к, місце=ПН.типове_місце(к))
    з = json.loads(B.виклик("запити", json.dumps(dict(вх0, каталог="каталог_повний.xml", сід=3, сценарій=сц,
                                                       випадок=к), ensure_ascii=False)))
    lo, hi = з["мета"]["формальність"]
    за_назвою = {н: r for _з, _б, _с in ФК._КЕШ_БАЗИ.values() for r in _б["каталог"]   # пул несе назву показу
                 for н in (r.get("назва"), r.get("назва_показу")) if н}
    пул = з["пакети"]["1"]["пул"]
    речі = [(с, за_назвою.get(р["назва"]) or {}) for с in СЛОТИ for р in пул.get(с) or ()]
    def оц(r):
        l, h = Ф.інтервал_формальності(r)
        ф = r.get("формальність_фото")
        return (l, h) if l is not None else ((ф, ф) if isinstance(ф, int) else None)
    нижче = sum(1 for _, r in речі if оц(r) and оц(r)[1] < lo)
    вище = sum(1 for _, r in речі if оц(r) and оц(r)[0] > hi)    # угору допуск корпусу лишився
    невід = sum(1 for _, r in речі if not оц(r))
    каз = collections.Counter(r.get("тип") for _, r in речі if r.get("тип") in КАЗУАЛЬНІ)
    print("%-13s %g–%g  речей %3d  нижче смуги %4.1f%%  вище %4.1f%%  невідомих %3.1f%%  казуальні: %s"
          % (к, lo, hi, len(речі), 100.0 * нижче / len(речі), 100.0 * вище / len(речі),
             100.0 * невід / len(речі), dict(каз) or "—"))
    картки[к] = tuple(р["назва"] for с in ("верх", "низ", "взуття", "сумка") for р in (пул.get(с) or [])[1:4])
    print("   перші речі (як бере заглушка стенда): %s" % "; ".join(т[:28] for т in картки[к][::3]))
пари = [(а, б) for i, а in enumerate(НАГОДИ) for б in НАГОДИ[i + 1:] if картки[а] == картки[б]]
print("ПАР НАГОД З ОДНАКОВИМИ ПЕРШИМИ РЕЧАМИ ПУЛУ: %d %s" % (len(пари), пари or ""))
