"""каталог_сусіди_черга.py — ЗАПИТ ДО МОДЕЛІ ДЛЯ ПРЕДСТАВНИКІВ ТОТОЖНИЙ ГОЛОВІ ГІЛКИ 5.4 (умова злиття 5.4-С).

Без моделі й мережі. Двічі кличе справжній `прогін(..., усі=True)` на каталозі з git у порожню теку з
заглушкою `_спитати`: без `сусіди` (як у голові гілки 5.4) і з `сусіди="значення"`. Звіряє ІМЕНА Й ЗАПИТИ
файлів: кожен файл другого прогону має в першому те саме ім'я з тим самим «── ЗАПИТ»; повний розбір ішов
лише для представників; решта — сусіди з `сусід_від`. Друкує лічби.
Запуск: python3 джерела/проби/каталог_сусіди_черга.py"""
import collections
import json
import os
import sys
import tempfile
import warnings

warnings.filterwarnings("ignore")
ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(ТУТ, ".."))

import каталог_розбір as КР                   # noqa: E402
import каталог_розбір_прогін as ПР            # noqa: E402
import каталог_розбір_сусіди as С             # noqa: E402


def _порожня(в):
    if isinstance(в, dict):
        return ({КР.ЦИТАТА: "", КР.ЗНАЧЕННЯ: "unknown"} if set(в) == {КР.ЦИТАТА, КР.ЗНАЧЕННЯ}
                else {к: _порожня(п) for к, п in в.items()})
    return [] if isinstance(в, list) else в


ПОВНА = json.dumps({КР.КОДИ: "item_type=unknown", КР.ОСОБЛИВОСТІ: "item=plain item"}, ensure_ascii=False)
КОЛІР = json.dumps({КР.КОДИ: "color_main=black=чорний"}, ensure_ascii=False)
виклики = collections.Counter()


def _спитати(повід, ід_моделі, схема=True, годинник=None, стадія="річ", макс_токенів=None, ім_схеми=None,
             придатна=None):
    виклики[стадія] += 1
    return (КОЛІР if стадія == "колір" else ПОВНА), 0.0, None, 0


def файли(тека):
    вих = {}
    for р in json.load(open(os.path.join(тека, "прогін.json"), encoding="utf-8"))["речі"]:
        вих[р["файл"]] = (open(os.path.join(тека, р["файл"]), encoding="utf-8").read()
                          .partition("\n\n── ВІДПОВІДЬ\n")[0], bool(р.get("сусід_від")))
    return вих


if __name__ == "__main__":
    ПР._спитати = _спитати
    ПР.зібрати = lambda тека: None           # збирач не потрібен: міряємо лише чергу
    with tempfile.TemporaryDirectory() as а, tempfile.TemporaryDirectory() as б:
        ПР.прогін("проба", куди=а, усі=True, паралельно=1)
        повних_голова = виклики["річ"]
        виклики.clear()
        ПР.прогін("проба", куди=б, усі=True, паралельно=1, сусіди="значення")
        голова, нові = файли(а), файли(б)
    представники = {ім for ім, (_, сусід) in нові.items() if not сусід}
    print("голова 5.4: файлів %d, викликів моделі %d" % (len(голова), повних_голова))
    print("5.4-С: файлів %d · повних викликів %d · колірних %d · сусідів %d"
          % (len(нові), виклики["річ"], виклики["колір"], len(нові) - len(представники)))
    print("імена файлів ті самі: %s" % (set(голова) == set(нові)))
    різні = [ім for ім in нові if голова.get(ім, (None,))[0] != нові[ім][0]]
    print("файлів із іншим ЗАПИТОМ, ніж у голові: %d" % len(різні))
    print("повних викликів = представники: %s" % (виклики["річ"] == len(представники)))
    sys.exit(bool(різні) or set(голова) != set(нові))
