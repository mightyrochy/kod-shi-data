# -*- coding: utf-8 -*-
"""Рядок 1840: від чого важіль макіяжу K-CLR-03 міряє помаду. ДО — від `value_обличчя` (волосся 0.75 +
шкіра 0.25, K-CLR-04, фольклорна вага); ПІСЛЯ — від шкіри (губи всередині овалу, R-CHEV-18; R-MUA-03
«contrast against the skin»). Профілі ж1–ж8 (`аудит/проби/жінки`) з помадою #b0203a (рівень «яскравий»):
ліміт `дозволений_контраст`, ряд «рекомендовані» `bridge._основи` і вирок K-CLR-02 судді
(`колір_образу.біля_обличчя`) на верхах каталогу руки 1 біля обличчя — ДО (опора підмінена) і ПІСЛЯ.
Запуск із `джерела`: python3 проби/помада_від_шкіри_1840.py"""
import sys, os, json, copy
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import colorspace as cs, bridge as B, outfit as O, face_contrast as FC, колір_образу as K, collections
import feed; feed.каталог_на_диску('каталог_повний.xml'); import фід_каталог as ФК
ВЕРХИ = collections.Counter()                 # вирок K-CLR-02 залежить від L*: речі гуртом за L*
for r in ФК._прочитати_каталог('каталог_повний.xml', 0)['каталог']:
    if r.get("слот") in ("верх", "сукня", "верхній_шар") and r.get("lab"): ВЕРХИ[round(r["lab"][0])] += 1
def суд(L, ос):
    з = [z for z in K.біля_обличчя(O.елементи([dict(id="в", слот="верх", hex=cs.hex_з_lab((L, 0, 0)))]), ос) if z.get("правило") == "K-CLR-02"]
    return з[0]["сила"] + ("в" if "вищ" in з[0]["суть"] else "н") if з else "нема"
ПОМАДА = {"рівень": "яскравий", "губи": "#b0203a"}
справжній = FC.дозволений_контраст; змін, разом, судом = 0, 0, 0
def до(контраст, макіяж=None, L_шкіри=None):          # опора ДО: зона обличчя замість шкіри
    к = dict(контраст or {}); к["L_шкіри"] = к.get("L_обличчя")
    return справжній(к, макіяж)
for і in range(1, 9):
    ж = json.load(open("../аудит/проби/жінки/ж%d.json" % і, encoding="utf-8"))
    F0 = cs.features([cs.hx(х) for х in ж["skin"]], [cs.hx(х) for х in ж["hair"]], cs.hx(ж["eyes"]))
    F = cs.додати_макіяж(copy.deepcopy(F0), ПОМАДА)[0]
    ос = O.контраст_особи(F)
    р = {}
    for хто, ф in (("ДО", до), ("ПІСЛЯ", справжній)):
        FC.дозволений_контраст = ф
        р[хто] = (ф(ос)[0], {x["ключ"] for x in B._основи(copy.deepcopy(F))["рекомендовані"]}, {L: суд(L, ос) for L in ВЕРХИ})
    FC.дозволений_контраст = справжній
    без = {x["ключ"] for x in B._основи(copy.deepcopy(F0))["рекомендовані"]}
    д = len(р["ДО"][1] ^ р["ПІСЛЯ"][1]); змін += д; разом += len(р["ПІСЛЯ"][1])
    с = sum(n for L, n in ВЕРХИ.items() if р["ДО"][2][L] != р["ПІСЛЯ"][2][L]); судом += с
    print("ж%d шкіра L*%.0f обличчя L*%.0f контраст %.1f · ліміт без помади %.1f · з помадою ДО %.1f / ПІСЛЯ %.1f · "
          "рекомендованих без помади %d, ДО %d, ПІСЛЯ %d (змінилось %d) · вирок судді змінився на %d верхах" % (і, ос["L_шкіри"], ос["L_обличчя"],
          ос["value_gap"], ос["value_gap"], р["ДО"][0], р["ПІСЛЯ"][0], len(без), len(р["ДО"][1]), len(р["ПІСЛЯ"][1]), д, с))
print("ФАКТ · помада #b0203a: від опори важеля міняються %d основ ряду «рекомендовані» (з %d) і вирок K-CLR-02 на %d "
      "верхах каталогу з %d×8" % (змін, разом, судом, sum(ВЕРХИ.values())))
