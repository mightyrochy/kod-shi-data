# -*- coding: utf-8 -*-
"""Рядок 160 (вердикти тестувальниці «Ір», 22–23.09.2026): приміряння малює не ті речі — «Інший плащ намальовано
та кардиган», «Кардиган інший». Звідси видно чому: у модель картинки йшли лише ПЕРШІ 8 придатних знімків образу,
решта домальовувалась із голови. Проба рахує на шести сценах стенда, скільки знімків образу доїжджає в запит
ДО стелі 8 і ПІСЛЯ стелі 12. Запуск із теки `джерела`: `python3 проби/prymiriannia_160.py`."""
import sys, os, json, re
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import стенд_знімок as СЗ, міст_опис as МО, bridge as B   # шлях показу, не копія його логіки
НЕПРИДАТНЕ = re.compile(r"^data:|^//|\.gif($|\?)", re.I)   # формати, яких модель картинки не приймає
СТЕЛЯ_ДО, СТЕЛЯ_ПІСЛЯ = 8, 12                              # `показ.ФОТО_НА_ПРИМІРКУ` до і після правки
СЛОТИ = ("сукня", "верх", "низ", "верхній_шар", "взуття", "сумка", "прикраси", "пояс", "шарф")
КАТ = "каталог_повний.xml" if os.path.exists("каталог_повний.xml") else "каталог_brief.xml"

def образ_сцени(сцен):
    """Картки речей сцени — тим самим `міст_опис.показ`, яким їх бачить показ; образ
    складається детерміновано: перший кандидат кожного слота пулу."""
    вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["сценарій"] = сцен
    к = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False))).get("кандидати") or {}
    ід = [к[с][0]["id"] for с in СЛОТИ if к.get(с) and к[с][0].get("id")]
    return json.loads(МО.показ(dict(каталог=КАТ, речі=ід))) if ід else []

print("сцена                     речей  зі знімком  придатних   ДО  ПІСЛЯ  поза · причини"); разом = [0, 0, 0]
for назва, сцен in list(СЗ.СЦЕНАРІЇ.items())[:6]:
    речі = образ_сцени(сцен)
    зі_знімком = [р for р in речі if р.get("фото")]
    придатні = [р for р in зі_знімком if not НЕПРИДАТНЕ.search(str(р["фото"]))]
    до, після = придатні[:СТЕЛЯ_ДО], придатні[:СТЕЛЯ_ПІСЛЯ]
    поза = [р for р in речі if р not in після]
    чому = {}
    for р in поза:
        к = "знімка нема" if not р.get("фото") else "формат не приймає"; чому[к] = чому.get(к, 0) + 1
    разом = [разом[0] + len(речі), разом[1] + len(до), разом[2] + len(після)]
    print("%-24s %6d %11d %10d %4d %6d %5d · %s" % (назва[:24], len(речі), len(зі_знімком),
          len(придатні), len(до), len(після), len(поза),
          ", ".join("%s %d" % (к, v) for к, v in sorted(чому.items())) or "—"))
    assert len(після) >= len(до), "стеля після правки не може бути вужчою"
print("РАЗОМ речей %d · знімків у запит картинки: ДО %d · ПІСЛЯ %d\nРечі поза запитом названі тепер"
      " ПОІМЕННО — у рядку біля картинки і в журналі (`примірка_без_фото`)." % tuple(разом))
assert разом[2] >= разом[1] and разом[2] > 0
print("prymiriannia_160: зелено")
