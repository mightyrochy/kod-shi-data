# -*- coding: utf-8 -*-
"""ПРИСКОРЕННЯ `запити` БЕЗ ЗМІНИ РЕЗУЛЬТАТУ: час і хеш пулу до/після.

Інваріант названий числом, а не обіцянкою: набір речей у пулі (`ПАКЕТ_V1.пул[*].н`)
і ПОРЯДОК у кожному слоті лишаються ті самі. `ДО` зняте на origin/main 7ce345e — на
тому самому коді, мінус правки швидкості (злито перед виміром: збагачення в main
рухає пул саме́ по собі). Гілки «не обирала» і 0 в одному процесі: друга тепла.
ФІД РОЗПАКОВУЄТЬСЯ ЗАНОВО, а не беруться ті 44 МБ з теки: крок збірки
`чистка_каталогу.почистити` переписує фід НА МІСЦІ, і пул на почищеному інший
(3d285c6a49652675) — інваріант же тут про КОД, а не про те, чи хтось збирав показ.
Запуск: PYTHONPATH=. python3 проби/shvydkist_пул.py
"""
import json, time, hashlib, gzip, os, shutil, tempfile
import bridge as B

ДО = {None: ("0c20789fd51e93c7", 339, 27.1), 0: ("ef454b916847dd29", 348, 16.2)}
шлях = os.path.join(tempfile.gettempdir(), "shvydkist_каталог.xml")
with gzip.open("../каталог_повний.xml.gz", "rb") as г, open(шлях, "wb") as в:
    shutil.copyfileobj(г, в)
розбіжних = 0
try:
    for гілка in (None, 0):
        вх = dict(json.load(open("стенд_вх.json")), каталог=шлях, гілка=гілка)
        t = time.perf_counter()
        вих = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
        дт = time.perf_counter() - t
        пул = json.loads(вих["B"])["пул"]
        рядок = json.dumps({с: [r["н"] for r in v] for с, v in пул.items()}, ensure_ascii=False)
        хеш, речей = hashlib.sha256(рядок.encode()).hexdigest()[:16], sum(len(v) for v in пул.values())
        хеш_до, речей_до, час_до = ДО[гілка]
        той_самий = (хеш == хеш_до and речей == речей_до)
        розбіжних += 0 if той_самий else 1
        print("гілка %-4s пул %d→%d речей · хеш %s→%s · %s · час %.1f→%.1f с (×%.1f)"
              % (гілка, речей_до, речей, хеш_до, хеш,
                 "ТОЙ САМИЙ ПУЛ" if той_самий else "⚠ ПУЛ РОЗІЙШОВСЯ",
                 час_до, дт, час_до / дт if дт else 0.0))
finally:
    os.path.exists(шлях) and os.unlink(шлях)
print("інваріант: %s (розбіжних гілок %d із %d)"
      % ("тримається" if not розбіжних else "ПОРУШЕНО", розбіжних, len(ДО)))
