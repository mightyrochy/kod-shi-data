# -*- coding: utf-8 -*-
"""K-SIZ-02 — «a nominal size does not predict fit»: вхід був і не читався.

ДО: мітка розміру стоїть у картці й не доїжджає нікуди — вердикт про розмір
мовчить, і мовчання читається моделлю як дозвіл сказати «сяде».
ПІСЛЯ: мітки розбираються (`feed.розміри_одягу`), і на образі з тією самою
сукнею виходить ПИТАННЯ зі смугою — регістр «питання», не блокує, не ранжує.
Жодного числа розкиду тут нема НАВМИСНО: корпус мітить їх `[folkloric]`."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, суд_образу as С

кат = Ф._прочитати_каталог(Ф.каталог_на_диску("каталог_повний.xml"), ліміт_фото=0)["каталог"]
одяг = [c for c in кат if c["слот"] in Ф.СЛОТИ_РОЗМІРУ_ОДЯГУ]
з_міткою = [c for c in одяг if c.get("розміри")]
print("каталог: одягу %d · з мітками розміру %d (%.1f%%) · зі словом магазину про "
      "розмірність %d · із «нема» коло мітки %d"
      % (len(одяг), len(з_міткою), 100 * len(з_міткою) / len(одяг),
         sum(1 for c in одяг if c.get("розмірність")),
         sum(1 for c in одяг if c.get("розміри_нема"))))
assert з_міткою, "мітка розміру мусить доїжджати до запису каталогу"

сук = next(c for c in з_міткою if c["слот"] == "сукня" and len(c["розміри"]) > 2)
річ = dict(сук, id=сук["id"], hex="#808080")
print("сукня «%s» · мітки %s → смуга «%s»"
      % (сук["назва"][:40], ", ".join(сук["розміри"]), Ф.смуга_розмірів(сук)))

# «до» — стан, у якому поля не було: суд про розмір мовчить
z_до = С.розмір_не_посадка([dict(річ, розміри=None)])
print("до:  знахідок про розмір %d — розмір мовчить" % len(z_до))
assert not z_до

z = С.розмір_не_посадка([річ])
assert len(z) == 1, "одна знахідка на образ"
z = z[0]
print("після: %s [%s] сила_нп %s, блокує=%s" % (z["правило"], z["регістр"], z["сила_нп"], z["блокує"]))
print("   суть:    %s" % z["суть"])
print("   питання: %s" % z["питання_людині"])
assert z["регістр"] == "питання" and not z["блокує"], "правило не ранжує й не забороняє"
assert Ф.смуга_розмірів(сук) in z["суть"], "смуга мусить стояти в тексті"
assert z["сила_нп"] is not None and z.get("сила_нп_джерело")

# слово магазину «маломірить» іде в питання його ж словами, а не нашим переказом
мм = next((c for c in одяг if c.get("розмірність") and c.get("розміри")), None)
if мм:
    z2 = С.розмір_не_посадка([dict(мм, hex="#808080")])[0]
    print("свідок магазину: «%s» → %s" % (мм["розмірність"], z2["чому"][-90:]))
    assert мм["розмірність"] in z2["чому"]
