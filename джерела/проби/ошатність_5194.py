"""5194: пул руки 1 на побаченні, роботі, святі й похороні — ДО/ПІСЛЯ щаблів ошатності речей (`форм. a–b` з
`кандидати`), складу пулу й лічби `відсічено`. `--до` зберігає зріз у `дані_5191_5194/пул_5194_до.json.gz`; без
прапора — порівняння з ним і щаблі всього каталогу. Смуга нагоди — число мовної моделі, однакове ДО й ПІСЛЯ.
Запуск: cd джерела && python3 проби/ошатність_5194.py [--до]"""
import gzip, json, os, re, shutil, sys, tempfile
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import bridge as B
СЦЕНИ = {"побачення": {"нагода": "побачення", "місце": "ресторан_районний", "година": 19, "ошатність": [5, 6]},
         "робота": {"нагода": "робота", "місце": "офіс", "година": 9, "дрес_код": "business_casual", "ошатність": [5, 7]},
         "свято": {"нагода": "свято", "місце": "святкова_вечеря", "година": 19, "ошатність": [6, 8]},
         "похорон": {"нагода": "траур", "місце": "похорон", "година": 11, "ошатність": [5, 7]}}
ФАЙЛ, ФОРМ = "дані_5191_5194/пул_5194_до.json.gz", re.compile(r"форм\. (\d+)–(\d+)")
def пули():
    тека = tempfile.mkdtemp(prefix="oshat5194_"); шлях = os.path.join(тека, "к.xml")
    with gzip.open("../каталог_повний.xml.gz", "rb") as г, open(шлях, "wb") as в: shutil.copyfileobj(г, в)
    вихід = {}
    for н, сц in СЦЕНИ.items():
        вх = dict(json.load(open("стенд_вх.json")), каталог=шлях, гілка=None, сценарій=dict(сц, темп_c=18), випадок=н)
        вих = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
        вихід[н] = {"речі": {р["id"]: [слот, [int(x) for x in м.groups()] if (м := ФОРМ.search(р["зона"] or "")) else None]
                             for слот, v in вих["кандидати"].items() for р in v},
                    "відсічено": (вих.get("відсічено") or {}).get("лічба") or {}}
    shutil.rmtree(тека, ignore_errors=True); return вихід
def щаблі():
    import feed, фід_каталог as FK, outfit as O, формальність as ФМ
    к = ("тип", "тип_модифікатор", "формальність_фото", "текстура", "матеріал", "волокно", "тканина_за_чим")
    return {r["id"]: list(ФМ.інтервал_формальності(dict({x: r.get(x) for x in к}, річ=r["id"],
            формальність=r.get("формальність") or O.ТИП_ФОРМАЛЬНІСТЬ.get(r.get("тип"))))) for r in FK._прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"]}
if "--до" in sys.argv:
    gzip.open(ФАЙЛ, "wt", encoding="utf-8").write(json.dumps(dict(пули=пули(), щаблі=щаблі()), ensure_ascii=False)); sys.exit(print("ДО збережено"))
до, після, щ = json.load(gzip.open(ФАЙЛ, "rt", encoding="utf-8")), пули(), щаблі()
for н in СЦЕНИ:
    а, б, в1, в2 = до["пули"][н]["речі"], після[н]["речі"], до["пули"][н]["відсічено"], після[н]["відсічено"]
    print("%-9s пул %d→%d · вийшли %d · увійшли %d · змінили щабель %d із %d спільних" % (н, len(а), len(б), len(set(а) - set(б)),
          len(set(б) - set(а)), sum(1 for і in set(а) & set(б) if а[і][1] != б[і][1]), len(set(а) & set(б))))
    print("          відсічено: " + (", ".join("%s %s→%s" % (к, в1.get(к, 0), в2.get(к, 0)) for к in sorted(set(в1) | set(в2)) if в1.get(к, 0) != в2.get(к, 0)) or "без змін"))
print("каталог: щабель змінили %d із %d речей" % (sum(1 for і, v in щ.items() if v != до["щаблі"].get(і)), len(щ)))
