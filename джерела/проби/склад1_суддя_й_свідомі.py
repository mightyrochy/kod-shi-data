"""Рядок 1971 (2), (3): запасний шлях без судді (CQ04) і «свідомий розрив» за id правила на замінникові (CQ06). Пул — стенд
(`стенд_вх.json`, офіс, сід 3). Суддя-заглушка: гейт K-COL-01 на першому верху пулу, K-PAL-03 — на кожному верху, крім
першого й другого. (2) Відповідь без образу, запасний вердикт — образ із гейтом K-COL-01 на верху, який код міняє.
(3) Модель оголосила K-PAL-03 на своєму низу навмисним; гейт K-COL-01 на верху; заміна верху приносить K-PAL-03 на
замінникові, про якого вона не казала. Факт — `повний` у (2) і чи взято варіант із неоголошеним гейтом у (3)."""
import json, sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, повнота_образу as ПО
вх = dict(json.load(open("стенд_вх.json")), сід=3)
к = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["кандидати"]
в0, в1 = к["верх"][0]["id"], к["верх"][1]["id"]
низ, взуття, сумка = (к[с][0]["id"] for с in ("низ", "взуття", "сумка"))
def суддя(набори, низ_свідомо=False):
    вих = []
    for н in набори:
        з = [dict(правило="K-COL-01", регістр="гейт", речі=[в0])] if в0 in н else []
        з += [dict(правило="K-PAL-03", регістр="гейт", речі=[і]) for і in н if і in {r["id"] for r in к["верх"][2:]}]
        з += [dict(правило="K-PAL-03", регістр="гейт", речі=[низ])] if низ_свідомо else []
        ок = any(і in {r["id"] for r in к["верх"]} for і in н)
        вих.append(dict(ід="о1", речі=list(н), знахідки=з, структура=dict(ок=ок, блокери=[] if ок else [dict(код="нема_верху")])))
    return вих
зап = dict(образи=суддя([[в0, низ, взуття, сумка]]))
п = ПО.повнота_набору(dict(образи=[]), кандидати=к, запасний=зап, суддя=суддя, дібрати=True)
print("(2) відповідь без образу, запасний із гейтом, що лікується: повний=%s · склад %s"
      % (п.get("повний"), "з заміною верху" if в0 not in п["ід"] else "старий"))
о = суддя([[в0, низ, взуття, сумка]], низ_свідомо=True)[0]
о["знахідки"][-1]["свідомий"] = True
ід2, _зм, звіт = ПО._ремонт_гейтів([в0, низ, взуття, сумка], {}, о, dict(к, верх=[к["верх"][0]] + к["верх"][2:7] + [к["верх"][1]]),
                                   ПО._словник_речей(к), {}, lambda н: суддя(н, низ_свідомо=True))
верх2 = next((і for і in (ід2 or []) if і in {r["id"] for r in к["верх"]}), None)
print("(3) оголошено K-PAL-03 на низу; взято: %s → новий верх %s, неоголошений K-PAL-03 на ньому: %s"
      % ([{к_: v for к_, v in з.items() if к_ != "на"} for з in (звіт or {}).get("взято") or []], "нема" if not верх2 else ("другий у пулі (без гейту)" if верх2 == в1 else "з K-PAL-03"),
         "так" if верх2 and верх2 not in (в0, в1) else "ні"))
