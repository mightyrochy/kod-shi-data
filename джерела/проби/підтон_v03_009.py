# -*- coding: utf-8 -*-
"""Приймання Н-V03-009 (Ш3): міст віддає гейт джерела й слово тонової осі.
До правки обидва поля були відсутні у виході `палітри` — показ не мав чим
відрізнити «утримано через надійність знімка» від «пораховано й вийшло
серединно», і обидва стани лишали екран палітри однаково порожнім."""
import json, sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge

вх = json.load(open(os.path.join(os.path.dirname(__file__), "..", "стенд_вх.json"), encoding="utf-8"))
база = {k: вх[k] for k in ("зріст", "обхвати", "шкіра", "волосся", "очі")}
база.update(намір="conventional", без_фото=1)

r = json.loads(bridge.палітри(dict(база)))           # без драпіровки: баланс білого некерований
print("утримано:       ", r["гейт"]["утримано"])
print("можна:          ", r["гейт"]["можна_стверджувати"])
print("осі_джерело:    ", r["осі_джерело"])
print("осі_словами.hue:", (r["осі_словами"] or {}).get("hue"))

з_драпом = dict(база, драп_сирий={"метал": "золото", "білий": "теплий"})
d = json.loads(bridge.палітри(з_драпом))
print("з відповідями на три питання → осі_джерело:", d["осі_джерело"],
      "· слово:", (d["осі_словами"] or {}).get("hue"))

ок = (r["гейт"]["утримано"] == ["chroma", "hue", "undertone"]
      and r["осі_джерело"] == "утримано: підтон із фото не стверджується → нейтральна"
      and (r["осі_словами"] or {}).get("hue") == "не стверджується"
      and d["осі_джерело"] == "самозвіт")
print("ПРИЙМАННЯ:", "пройдено" if ок else "ПРОВАЛЕНО")
sys.exit(0 if ок else 1)
