# -*- coding: utf-8 -*-
"""K-COND-02, K-PCA-01, K-TIME-01 — три правила шару палітр, що лишали рівно слід.

K-COND-02 («засмага не робить теплою: міняється поверхня, підтон — ні»). Слід
СТВЕРДЖУВАВ властивість коду («ключ від очей») і нічого не перевіряв. Заява, яку
ніхто не міряє, зламається мовчки: слід писатиме те саме речення над іншою
поведінкою. Тепер властивість МІРЯЄТЬСЯ — шкіру темнимо на крок ITA (4.5 L*, тон
не чіпаємо: саме так діє засмага), перераховуємо осі й дуги сімей і порівнюємо. І
`доводить` чесно каже, коли збіг є наслідком УТРИМАНОЇ осі, а не доказом.

K-PCA-01 («останній ключ сортування, не фільтр»). Слід називав правило ключем
сортування, і жодного сортування не було: `знак_проксі` рахувався на кожному
кольорі, лягав у поле й нікуди не йшов. Порядок кольорів не декоративний —
`palettes.словами` перелічує сім'ї саме в ньому, і цей текст читає жінка.

K-TIME-01 («сивина → ПЕРЕМІРЯТИ, а не переназвати»). Механізм живий і виміряний:
ахроматичне волосся не несе температури (`warmth=None`), і контраст особи
перераховується. А ВИМОГА переміряти — `profile.аудит` рахує `переміряти` й
`вимога` — не входила в жоден вихід узагалі."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, colorspace as cs, palettes as ПЛ, outfit as O

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))

у = r.get("умови_палітри") or {}
print("K-COND-02 · інваріант: тримається=%s · зсув осі підтону %.2f · сімей змінилось %d "
      "· доводить=%s (%s)" % (у.get("тримається"), у.get("зсув_підтону") or 0,
                              у.get("сімей_змінилось"), у.get("доводить"),
                              str(у.get("джерело_осі"))[:34]))
assert у, "інваріант мусить виходити числом, а не лишатись у модулі"
assert у["тримається"], "зсув поверхні шкіри не має права перемикати дуги сімей"

F = cs.features(cs.hx(вх["шкіра"]), cs.hx(вх["волосся"][0]), cs.hx(вх["очі"]))
П = ПЛ.палітра_практична(F, самозвіт=dict(білий="вершковий", метал="золото"))
print("   з елісітацією вісь має вхід → доводить=%s" % П["умови"]["доводить"])
assert П["умови"]["доводить"], "з елісітацією перевірка мусить щось доводити"

п = П["знак_проксі_порядок"]
print("K-PCA-01 · кольорів «до здоровішого» %d / «від» %d · позицій зрушено %d"
      % (п["до_здоровішого"], п["від_здоровішого"], п["позицій_зрушено"]))
перші = [(c["назва"], c["знак_проксі"]["бік"]) for c in П["кольори"] if c.get("знак_проксі")][:3]
print("   перші три кольори палітри:", перші)
assert п["позицій_зрушено"] > 0, "останній ключ сортування мусить щось упорядковувати"
assert all(б == "до здоровішого" for _, б in перші), "після сортування перші — «до здоровішого»"

for волосся in ("#3b2a1a", "#b4b4b4"):
    Fh = cs.features(cs.hx(вх["шкіра"]), cs.hx(волосся), cs.hx(вх["очі"]))
    к = O.контраст_особи(Fh)
    print("K-TIME-01 · волосся %s: warmth=%s · контраст «%s» (value_gap %.1f)"
          % (волосся, Fh["волосся"].get("warmth"), к.get("рівень"), к.get("value_gap") or 0))
б = r.get("бракує_входів") or {}
print("   вимога переміряти у виході: ключі %s · зараз %s"
      % (["переміряти", "вимога_переміряти"],
         "порожньо (заявлених зсувів нема)" if not б.get("переміряти") else б["переміряти"]))
assert "переміряти" in б, "вимога «переміряти, а не переназвати» мусить мати вихід"
