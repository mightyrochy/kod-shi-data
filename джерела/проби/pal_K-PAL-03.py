# -*- coding: utf-8 -*-
"""K-PAL-03 (тон у тон) — гейт, зроблений 16.09, і далі спрацьовує.

Правило зроблено гейтом учора (`pipeline.схема_образу`); ця сесія його не
чіпала, але зачепила те, на чому він стоїть: означення нейтралі. Копію коридорів
у `pipeline._нейтральний_тон` знято на користь `колір_образу.нейтраль` — а саме
цей предикат вирішує, чи річ «законна під будь-яку схему». Проба стереже, що
гейт лишився гейтом і що темна холодна нейтраль (нейві: L*≤45, C*≤34) більше не
судиться як колір поза дугою.
Запуск із теки `джерела`: `python3 проби/pal_K-PAL-03.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import pipeline as PL, колір_образу as КО

# 1. ОДНЕ ОЗНАЧЕННЯ НЕЙТРАЛІ НА ДВА МІСЦЯ
нейві = (30.0, 6.0, -28.0)                      # L*30, C*28.6, h*282 — холодна нейтраль
print("нейві L*30 C*28.6 h*282 · колір_образу.нейтраль: %s · pipeline._нейтральний_тон: %s"
      % (КО.нейтраль(нейві), PL._нейтральний_тон(282.0, 28.6, 30.0)))
assert (КО.нейтраль(нейві) is not None) == PL._нейтральний_тон(282.0, 28.6, 30.0)

# 2. ГЕЙТ ЖИВИЙ НА СТЕНДІ
вх, r, кат, спец = ПВ.стенд(гілка=0, намір="statement")
дуга = ((спец.get("слоти") or {}).get("сукня") or {}).get("дуга_тону")
поза = lambda L, C, h, _: (not PL._нейтральний_тон(h, C, L) and dict(lo=float(дуга[0]), hi=float(дуга[1]))
                           and not ((float(дуга[0]) - 10 <= h <= float(дуга[1]) + 10)
                                    if дуга[0] <= дуга[1] else (h >= дуга[0] - 10 or h <= дуга[1] + 10)))
річ = next((x for с in ("сукня", "верх") for x in [ПВ.взяти(r, кат, с, поза)] if x), None)
решта = [ПВ.взяти(r, кат, с, lambda *a: True) for с in ("низ", "взуття", "сумка")]
ід = [x["id"] for x in [річ] + решта if x][:4]
print("схема «%s», дуга слота %s · річ поза дугою: %s L%.0f C%.0f h%.0f"
      % (спец.get("схема"), дуга, (річ or {}).get("назва", "—")[:32], *ПВ.lch(кат, річ["id"])))
зн, _ = ПВ.знахідки(вх, ід)
print("ФАКТ · K-PAL-03: %s" % ПВ.рядок(зн, "K-PAL-03"))
z = next((x for x in зн if x.get("правило") == "K-PAL-03"), None)
assert z and z["регістр"] == "гейт" and z["сила_нп"] == 0.95, z
