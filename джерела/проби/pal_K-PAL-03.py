# -*- coding: utf-8 -*-
"""K-PAL-03 (тон у тон) — гейт, зроблений 16.09, і далі спрацьовує.

Правило зроблено гейтом учора (`pipeline.схема_образу`); ця сесія його не
чіпала, але зачепила те, на чому він стоїть: означення нейтралі. Копію коридорів
у `pipeline._нейтральний_тон` знято на користь `колір_образу.нейтраль` — а саме
цей предикат вирішує, чи річ «законна під будь-яку схему». Проба стереже, що
гейт лишився гейтом і що темна холодна нейтраль (нейві: L*≤45, C*≤34) більше не
судиться як колір поза дугою.
Запуск із теки `джерела`: `python3 проби/pal_K-PAL-03.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import pipeline as PL, колір_образу as КО

# 1. ОДНЕ ОЗНАЧЕННЯ НЕЙТРАЛІ НА ДВА МІСЦЯ
нейві = (30.0, 6.0, -28.0)                      # L*30, C*28.6, h*282 — холодна нейтраль
print("нейві L*30 C*28.6 h*282 · колір_образу.нейтраль: %s · pipeline._нейтральний_тон: %s"
      % (КО.нейтраль(нейві), PL._нейтральний_тон(282.0, 28.6, 30.0)))
assert (КО.нейтраль(нейві) is not None) == PL._нейтральний_тон(282.0, 28.6, 30.0)

# 2. ГЕЙТ ЖИВИЙ НА СТЕНДІ
вх, r, кат, спец = ПВ.стенд(гілка=0, намір="statement")
дуга = ((спец.get("слоти") or {}).get("сукня") or {}).get("дуга_тону")
# РІЧ БЕРЕМО З ВИМІРЯНИМ КОЛЬОРОМ (27.09.2026, рядок 173). Відколи K-PAL-03 міряє
# КОЛІР-СЛОВО дугою його вікна, а не тоном центру (рядок 162, `суд_від_моделі.схема_образу`),
# річ, чий колір узято зі слова, може мати вимір поза дугою й лишатись законною: судиться
# вікно слова. Проба ж добирала річ САМЕ за виміряним тоном — і бралася за «Сукню лляну
# Ніццу» (h*140), чиє вікно слова лежить у дузі схеми цілком, тож гейт мовчав ПРАВИЛЬНО, а
# проба червоніла, наче гейт помер. Тепер вона бере річ, чий колір ВИМІРЯНО: там мірка
# проби й мірка суду — та сама.
def поза(L, C, h, зап):
    if PL._нейтральний_тон(h, C, L) or КО.не_вимір(зап):
        return False
    lo, hi = float(дуга[0]), float(дуга[1])
    return not ((lo - 10 <= h <= hi + 10) if lo <= hi else (h >= lo - 10 or h <= hi + 10))
# РІЧ ПОЗА ДУГОЮ БЕРЕТЬСЯ З КАТАЛОГУ, КОЛИ ЇЇ НЕМА В ПУЛІ (17.09.2026). Пул — це
# вже відповідь палітри, і відколи колір речей береться з опису фото, речей поза
# дугою схеми в ньому під `statement` не лишилось зовсім: `взяти` віддавало None,
# і проба падала на індексуванні. Судить код НЕ пул, а ОБРАЗ — `перевірити_від_моделі`
# бере річ із каталогу за id (та сама причина, що записана в `pal_вердикт.з_каталогу`),
# і гейт мусить спрацювати саме там. Порядок збережено: спершу пул, потім каталог.
річ = next((x for с in ("сукня", "верх")
            for x in [ПВ.взяти(r, кат, с, поза) or ПВ.з_каталогу(кат, с, поза)] if x), None)
assert річ, "ні в пулі, ні в каталозі нема речі поза дугою схеми — гейтові нема що судити"
решта = [ПВ.взяти(r, кат, с, lambda *a: True) for с in ("низ", "взуття", "сумка")]
ід = [x["id"] for x in [річ] + решта if x][:4]
print("схема «%s», дуга слота %s · річ поза дугою: %s L%.0f C%.0f h%.0f"
      % (спец.get("схема"), дуга, (річ or {}).get("назва", "—")[:32], *ПВ.lch(кат, річ["id"])))
зн, _ = ПВ.знахідки(вх, ід)
print("ФАКТ · K-PAL-03: %s" % ПВ.рядок(зн, "K-PAL-03"))
z = next((x for x in зн if x.get("правило") == "K-PAL-03"), None)
assert z and z["регістр"] == "гейт" and z["сила_нп"] == 0.95, z
