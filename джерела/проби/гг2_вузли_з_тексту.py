# -*- coding: utf-8 -*-
"""ГГ-2 (08.10): частка ребер гіперграфа знахідок, чиї вузли тіла взято з ТЕКСТУ (`суть`/`чому`), а не з кодів
`учасники.зони`. Живий суд (`pipeline.перевірити_від_моделі`) над образами з пулу стенда, без моделі: 3 сцени ×
4 образи, сід 7. Ребро «з тексту» — зона тіла у вузлах ребра, якої нема в `учасники.зони` його знахідки.
До ГГ-2 граф шукав назви зон підрядком у тексті — частка > 0; після — 0 (зону дає лише код)."""
import json, os, random, sys
Д = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, Д); os.chdir(Д)
import bridge as B, fit as ПС, colorspace as cs, pipeline as PL, graph as ГР, стенд_знімок as СЗ
вх0 = json.load(open("стенд_вх.json", encoding="utf-8"))
T = ПС.тіло(float(вх0["зріст"]), {k: float(v) for k, v in вх0["обхвати"].items()})
F = cs.features(cs.hx(вх0["шкіра"]), cs.hx(вх0["волосся"][0]), cs.hx(вх0["очі"]))
СЛОТИ = ("верх", "низ", "сукня", "верхній_шар", "взуття", "сумка", "шарф", "сережки", "кольє", "пояс")
ребер = з_тексту = з_кодом = 0
правила = {}
for назва in ("офіс·18°C", "дощ·ресторан·вечір", "весілля·гість"):
    сц = СЗ.СЦЕНАРІЇ[назва]
    к = json.loads(B.виклик("запити", json.dumps(dict(вх0, сценарій=сц, випадок=назва), ensure_ascii=False)))["кандидати"]
    кат, rnd = B.каталог_останнього_пакета(), random.Random(7)
    for n in range(4):
        пропуск = ("верх", "низ") if n % 2 == 0 else ("сукня",)
        ід = [rnd.choice(к[с])["id"] for с in СЛОТИ if к.get(с) and с not in пропуск]
        в = PL.перевірити_від_моделі(ід, F, кат, T, сценарій=dict(сц), кандидати=к)
        зн = в["знахідки"]
        for р in ГР.граф(зн, в["речі"])["ребра"]:
            з = зн[int(р["ід"].rsplit("#", 1)[1])]
            зони = set(р["вузли"]) & set(ГР.ЗОНИ_ТІЛА)
            код = set((з.get("учасники") or {}).get("зони") or ())
            ребер += 1
            з_кодом += bool(зони & код)
            if зони - код:
                з_тексту += 1
                правила[р["правило"]] = правила.get(р["правило"], 0) + 1
print("ребер %d · вузли тіла з тексту: %d (%.1f %%) · з кодів учасників: %d" % (ребер, з_тексту, 100.0 * з_тексту / max(1, ребер), з_кодом))
print("з тексту за правилами:", sorted(правила.items(), key=lambda x: -x[1]))
