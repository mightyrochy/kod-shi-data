"""Рядок 1424: чи діє K-BOD-02 у пулі — частка речей ярусу кроїв тіла (`cuts_best_on_her`) серед
верхів, низів і верхніх шарів пулу руки 1 проти того самого пулу без правила (ярус знято).
Рядок 1540: скільки речей пулу ранг лишає нейтральними через слово крою поза кроями слота
(«слово»), і скільки — бо слово лягає на крої обох боків ярусу («двозначне»).
Запуск: PYTHONPATH=. python3 проби/крій_пул_1424.py   (потрібен каталог_повний.xml)"""
import sys, json, subprocess, pathlib
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
ЖІНКИ = {"ж4": (165, dict(плечі=112, груди=114, талія=104, стегна=114)),
         "ж6": (172, dict(плечі=108, груди=96, талія=76, стегна=92)),
         "ж8": (154, dict(плечі=90, груди=84, талія=64, стегна=88))}
if len(sys.argv) > 2:                                   # дочірній процес: один пул, без кешу сусіда
    import bridge as B, fit as ПС, hypergraph as ГГ, outfit as O, композитор_слоти as КС
    зр, об = ЖІНКИ[sys.argv[1]]
    вх = dict(json.load(open(_К / "стенд_вх.json", encoding="utf-8")), каталог=str(_К / "каталог_повний.xml"),
              гілка=0, варіантів=6, зріст=зр, обхвати=об, випадок="робота, офіс",
              сценарій=dict(нагода="робота", місце="офіс", година=9, темп_c=12))
    я = ГГ.крої_для_пулу(ПС.тіло(зр, об))
    if sys.argv[2] == "без":                            # пул без рангу K-BOD-02 (місце дії — лише ярус)
        ГГ.крої_для_пулу = lambda *a, **k: None
    r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    кат, вих = {c["id"]: c for c in B.каталог_останнього_пакета()}, {}
    for с, з in (("верх", "верх"), ("низ", "низ"), ("верхній_шар", "верх")):
        к = [кат.get(x["id"], x) for x in r["кандидати"].get(с) or []]   # рядки каталогу: слот, тип
        пр = [КС.причина_рангу_крою(x, я[з]) if hasattr(КС, "причина_рангу_крою") else  # ДО рядка 1540
              ("cut_word_outside_slot" if O.крій_речі(x) and O.крій_речі(x) not in я[з]["оцінені"] else "") for x in к]
        вих[с] = [sum(1 for x, п in zip(к, пр) if п == "cut_in_body_tier" or (not п and O.крій_речі(x) in я[з]["ярус"])), len(к),
                  пр.count("cut_word_outside_slot"), пр.count("cut_word_straddles_tier")]
    print(json.dumps(dict(ярлик=ПС.зони(ПС.тіло(зр, об))["ярлик"], ярус={з: sorted(я[з]["ярус"]) for з in я}, пул=вих),
                     ensure_ascii=False))
    sys.exit()
for ж in ЖІНКИ:
    р = {m: json.loads(subprocess.run([sys.executable, __file__, ж, m], capture_output=True, text=True,
                                       cwd=str(_К)).stdout.strip().splitlines()[-1]) for m in ("з", "без")}
    print(ж, р["з"]["ярлик"], "ярус", р["з"]["ярус"])
    for с in р["з"]["пул"]:
        a, b = р["з"]["пул"][с], р["без"]["пул"][с]
        print("   %-12s у ярусі: рука 1 %d/%d  ·  без K-BOD-02 %d/%d  ·  нейтрально: слово %d, двозначне %d"
              % (с, a[0], a[1], b[0], b[1], a[2], a[3]))
