# -*- coding: utf-8 -*-
"""ДОЩ-1 (рядок 1470): K-WEA-01 на дощовий день без шару від дощу. Збережений прогін, без моделі.
Бере образи рук 1–2 з `вердикти.txt.gz` (речі й слоти), погоду — з паспорта прогону; мітку вологи
верхнього шару кладе так, як `pipeline` (`верхнє_погода.теплова_функція`). Друкує знахідки K-WEA-01
кожного образу й того самого образу з верхнім шаром поверх (тренч, пальто, пуховик — тихо; куртка — знахідка).
Запуск: python3 проби/wea_дощ_без_шару.py [<тека прогону>]"""
import sys, os, gzip, json, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import outfit as O, суд_погода as СП, верхнє_погода as ВП
т = sys.argv[1] if len(sys.argv) > 1 else str(pathlib.Path(__file__).resolve().parents[2]
                                             / "аудит/перевірки/typove_1/ПІСЛЯ/ж5_дощ_знову")
ф = json.loads(gzip.open(os.path.join(т, "вердикти.txt.gz"), "rt", encoding="utf-8").read())
п = ф["спільне"]["паспорт"]
темп, опади = п.get("темп_c"), п.get("опади")
print("%s · темп_c %s · опади %s" % (os.path.basename(т.rstrip("/")), темп, опади))
def з_міткою(р):
    if р.get("слот") != "верхній_шар":
        return р
    тф = ВП.теплова_функція([р])
    return dict(р, тепловий_внесок=тф["тепловий_внесок"], теплова_мітка=тф.get("тепло"),
                **({"волога_мітка": тф["волога"]} if тф.get("волога") else {}))

def суд(речі):
    речі = [з_міткою(р) for р in речі]
    return [z for z in СП.погода(O.елементи(речі, стан="надворі"), темп_c=темп, опади=опади,
                                 стан="надворі", речі=речі) if z["правило"] == "K-WEA-01"]

верх = lambda т: dict(id="контроль-" + т, слот="верхній_шар", назва=т, hex="#a08060", тип=т, тип_верхнього=т)
for пр in ф["прогони"]:
    for в in пр["вердикти"]:
        if в.get("рука") not in ("1", "2"):
            continue
        речі = [dict(id=р["id"], слот=р["слот"], назва=р.get("назва"), hex="#777777",
                     тип=(р.get("укладка") or {}).get("тип")) for р in в.get("речі_образу") or []]
        print("рука %s · слоти %s" % (в["рука"], "+".join(р["слот"] for р in речі)))
        for підпис, набір in [("як є", речі)] + [("+ " + т, речі + [верх(т)]) for т in ("тренч", "пальто",
                                                                                       "пуховик", "куртка")]:
            print("   %-9s → %s" % (підпис, " | ".join("%s [%s %s] %s" % (
                z["суть"], z["регістр"], z["сила_нп"], [з["code"] for з in z.get("заяви") or []])
                for z in суд(набір)) or "тихо"))
