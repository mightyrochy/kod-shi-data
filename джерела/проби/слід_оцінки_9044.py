"""Рядок 9044: `запити` посеред прогріву каталогу `оцінка_а` (між поступками головному потоку, як у показі: воркер моста
починає наступне повідомлення, поки `виклик_а` поступається). Порівнює з тими самими викликами без перетину: хвіст сліду,
який кеш пакета (`міст_пакет._СЛІД_ПАКЕТА`) запам'ятав за побудову оцінки, і слід сесії `запити` після кінця оцінки.
Доти прогрів писав у список сліду, який `trace.почати` нового виклику вже підмінив: хвіст пакета брав чужі записи,
а слід `запити` — записи прогріву. Входи — записаний прогін сід 3 (`аудит/проби/знімок_входи_сід3.jsonl.gz`).
Запуск: cd джерела && python3 проби/слід_оцінки_9044.py   (каталог_brief.xml розпакований поруч)"""
import sys, os, json, gzip, asyncio
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import bridge, міст_пакет as МП, trace as СЛ, кеш_входу as КВ
рядки = [json.loads(р) for р in gzip.open(os.path.join(ТУТ, '..', 'аудит', 'проби', 'знімок_входи_сід3.jsonl.gz'), 'rt', encoding='utf-8')]
вх_з = json.dumps(next(json.loads(р['вхід']) for р in рядки if р['ім'] == 'запити'), ensure_ascii=False)
кандидати = [json.loads(р['вхід']) for р in рядки if р['ім'] == 'оцінка' and р.get('async') and json.loads(р['вхід']).get('крок') == 'каталог']
def скинути(): МП.КЕШ_ПАКЕТА.clear(); МП._СЛІД_ПАКЕТА.clear(); КВ.скинути()
def слід(): return [repr(з) for з in СЛ.ЗАПИСИ]
скинути(); bridge.виклик('запити', вх_з); чистий = слід()
for вх_о in кандидати:   # перший записаний прогрів — без сценарію, пакета не будує
    скинути(); asyncio.run(bridge.виклик_а('оцінка', вх_о))
    if МП._СЛІД_ПАКЕТА: break
чисті = {к: repr(в) for к, в in МП._СЛІД_ПАКЕТА.items()}; assert чисті, 'жоден записаний прогрів не збудував пакета'
async def перетин(поступок):
    о = asyncio.ensure_future(bridge.виклик_а('оцінка', вх_о))
    for _ in range(поступок): await asyncio.sleep(0)
    bridge.виклик('запити', вх_з); await о
    return слід()
хиб = порівняно = 0
for поступок in (1, 3, 6):
    скинути(); с = asyncio.run(перетин(поступок))
    пак = {к: repr(в) for к, в in МП._СЛІД_ПАКЕТА.items() if к in чисті}
    той = all(пак[к] == чисті[к] for к in пак); порівняно += bool(пак); хиб += (not той) + (с != чистий)   # нема ключа — пакет `запити` витіснив його з кеша
    print('запити після %d поступок: хвіст пакета оцінки той самий %s%s · слід сесії запити той самий %s (%d записів, без перетину %d)'
          % (поступок, той, '' if пак else ' (витіснено пакетами запити)', с == чистий, len(с), len(чистий)))
sys.exit(1 if хиб or not порівняно else 0)
