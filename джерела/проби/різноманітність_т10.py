# -*- coding: utf-8 -*-
"""Приймальна проба Т-10: різноманітність набору й герой — знахідки, а не слід у лог.

Друкує ФАКТИ на живому шляху (`bridge.від_моделі`, каталог_повний, коктейль 19:00):
   1) 10 образів, де ТРИ різняться однією сумкою → одна група з трьох;
   2) 10 образів різного складу → `ок=true`, груп нема;
   3) образ без жодної виразної речі → у `образи_без_героя`.
Плюс сила знахідок K-VAR-01 / K-COMP-02 і помилки схеми ВЕРДИКТ_V1 (мають бути 0).
Запуск із теки `джерела`: PYTHONPATH=. python3 проби/різноманітність_т10.py
"""
import json
import bridge as B, протокол as P

вх = json.load(open("стенд_вх.json"))
d0 = dict(вх, сценарій=dict(нагода="вечірка", місце="ресторан", година=19, темп_c=18,
                            дрес_код="cocktail"), випадок="коктейль, ресторан, 19:00")
пул = json.loads(json.loads(B.виклик("запити", json.dumps(d0, ensure_ascii=False)))["руки"]["1"])["пул"]
н = lambda с, k: пул[с][k % len(пул[с])]["н"]
суд = lambda образи: json.loads(B.виклик("від_моделі", json.dumps(
    dict(d0, текст_моделі=json.dumps(dict(версія="1", образи=образи), ensure_ascii=False)),
    ensure_ascii=False)))["вердикт"]
образ = lambda *реч: dict(ід="о", речі=list(реч))


def рядок(вд):
    наб = вд.get("набір") or {}
    рз, гр = (наб.get("різноманітність") or {}), (наб.get("герой") or {})
    зн = [(z["правило"], z["сила_нп"]) for z in (наб.get("знахідки") or [])]
    return ("образів %d · різноманітність ок=%s групи=%s · герой ок=%s без=%s двоє=%s · "
            "знахідки набору %s · помилок схеми %d"
            % (len(вд["образи"]), рз.get("ок"), рз.get("групи"), гр.get("ок"),
               гр.get("образи_без_героя"), гр.get("образи_з_двома"), зн,
               len(P.перевірити(P.СХЕМИ["ВЕРДИКТ_V1"], вд))))


# 1) три образи різняться ЛИШЕ сумкою, решта сім — різного складу
трійка = [образ(н("верх", 0), н("низ", 0), н("взуття", 0), н("сумка", k)) for k in range(3)]
решта = [образ(н("верх", k), н("низ", k), н("взуття", k), н("сумка", k)) for k in range(3, 10)]
вд = суд(трійка + решта)
print("три різняться сумкою: %s" % рядок(вд))
print("   чому: %s" % ((вд.get("набір") or {}).get("різноманітність") or {}).get("чому"))
# 2) десять образів різного складу
вд2 = суд([образ(н("верх", k), н("низ", k), н("взуття", k), н("сумка", k)) for k in range(10)])
print("десять різних:       %s" % рядок(вд2))
# 3) герой: чи є образи без жодної виразної речі
print("   риси образів проби 2: %s"
      % [(о["номер"], (о.get("риси") or {}).get("герой"), (о.get("риси") or {}).get("літера"),
          (о.get("риси") or {}).get("схема")) for о in
         json.loads(B.виклик("від_моделі", json.dumps(dict(d0, текст_моделі=json.dumps(
             dict(версія="1", образи=[образ(н("верх", k), н("низ", k), н("взуття", k))
                                      for k in range(3)]), ensure_ascii=False)),
             ensure_ascii=False)))["образи"]])
