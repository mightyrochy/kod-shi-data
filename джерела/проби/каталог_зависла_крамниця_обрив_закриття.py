"""В1: справжній повтор після таймауту закриття без SQLite-черги."""
import tempfile
from pathlib import Path
from каталог_зависла_крамниця_json_проба import обхід


def main():
    """Перевіряє ненульовий залишок після таймауту та виконання наступного запуску."""
    with tempfile.TemporaryDirectory(prefix="обрив-закриття-") as ж:
        арг = ["--журнал", ж, "--магазини", "hang.com", "--циклів", "1",
               "--секунд-на-магазин", "1", "--секунд-на-цикл", "3"]
        обхід.main(арг + ["--заглушка", "закриття"])
        до = обхід.прочитати_стан(ж)["hang.com"]
        assert до["причина_код"] == "TIMEOUT" and до["лишилось"] > 0
        assert not (Path(ж) / "проходи/hang.com/черга.sqlite3").exists()
        обхід.main(арг + ["--заглушка", "успіх"])
        після = обхід.прочитати_стан(ж)["hang.com"]
        assert після["стан_код"] == "CATALOG" and після["готово"] > до["готово"]
        print(f"В1: WAIT/TIMEOUT, лишилось={до['лишилось']} → CATALOG, готово={після['готово']}")


if __name__ == "__main__":
    main()
