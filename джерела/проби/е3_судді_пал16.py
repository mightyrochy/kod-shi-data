"""K-PAL-16 у `композитор_оцінка.оцінити`: вага ДО (|сила| palettes поверх `зн`, потім стеля) проти ПІСЛЯ
(`частка=|сила|` у `зн`) на всій області виразу palettes: ч ∈ [0, межова частка) кроком 0.0001, обидва множники."""
import collections, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import палітра_схеми  # noqa: F401 — порядок імпорту, як у продукті
from реєстр_правил import C as _C
М = _C['k_pal_16_межова_частка']   # колишня `palettes.МЕЖОВА_ЧАСТКА` (#3950): тепер константа реєстру
from реєстр_сила import зн, обмежити_вагу


def main():
    зміни, усього = collections.Counter(), 0
    for к in range(int(М * 10000)):
        ч = к / 10000.0
        for множник in (1.0, 0.6):
            с = abs(round(0.5 * (1.0 - ч / М) * множник, 3))
            до = обмежити_вагу([dict(зн('K-PAL-16', 'hint', 'с', [], 'ч', поріг=М, вимір=ч, повна=1.0),
                                     сила_нп=с)])[0]['сила_нп']
            після = обмежити_вагу([зн('K-PAL-16', 'hint', 'с', [], 'ч', поріг=М, вимір=ч, повна=1.0,
                                      частка=с)])[0]['сила_нп']
            усього += 1
            if до != після:
                зміни[round(після - до, 3)] += 1
    print('входів', усього, 'змінених ефективних ваг', sum(зміни.values()), 'зсув → кількість', dict(sorted(зміни.items())))
    print('максимальний зсув', max((abs(к) for к in зміни), default=0))


if __name__ == '__main__':
    main()
