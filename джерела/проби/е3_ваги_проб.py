"""Зіставлення кожної записаної погодної ваги у гейтах і пробах ДО/ПІСЛЯ."""
import collections, gzip, json, sys


def читати(шлях):
    """Прочитати записи й коди завершення обгортки."""
    with gzip.open(шлях, 'rt', encoding='utf-8') as ф:
        д = json.load(ф)
    return д.get('записи', д.get('rows', [])), д.get('провали', д.get('failed', []))


def ключ(р):
    """Ідентичність знахідки; порядок переліку речей не є виміром ваги."""
    речі = sorted(р[4] or [], key=lambda x: json.dumps(x, sort_keys=True))
    return json.dumps(р[:4] + [речі, р[5]], ensure_ascii=False, sort_keys=True)


def main():
    """Звірити склад і мультимножину ефективних ваг, назвати сирі зміни."""
    (до, збої_до), (після, збої_після) = map(читати, sys.argv[1:3])
    assert до and після, 'записувач не зібрав ваг'
    print('Провали ДО:', збої_до, 'ПІСЛЯ:', збої_після)
    print('| Перевірка | ДО | ПІСЛЯ | Сирих змін | Ефективних відмінностей |')
    print('|---|---|---|---|---|')
    вади = []
    for назва in sorted({р[0] for р in до + після}):
        д, п = ([р for р in дані if р[0] == назва] for дані in (до, після))
        сирі = [collections.Counter((ключ(р), р[6]) for р in рядки) for рядки in (д, п)]
        еф = [collections.Counter((ключ(р), р[7]) for р in рядки) for рядки in (д, п)]
        розбіжні = sum((еф[0] - еф[1]).values()) + sum((еф[1] - еф[0]).values())
        print('| %s | %d | %d | %d | %d |' % (назва, len(д), len(п), sum((сирі[0] - сирі[1]).values()), розбіжні))
        if розбіжні: вади.append(назва)
    print('записів', len(до), '→', len(після), 'відмінності:', вади)
    assert not вади, вади


if __name__ == '__main__':
    main()
