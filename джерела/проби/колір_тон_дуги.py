# -*- coding: utf-8 -*-
"""Звіряє лічбу кола `колір_тон` (кут, дуга) і `колір_простір_перетворення.lab_з_lch` з копіями читачів.

Для кожної нової функції — копія з файлу читача (рядок дошки, що її назвав) і число розбіжностей на тих самих
входах: ціла сітка кутів, дуги з цілими й дробовими кінцями, вироджені (x, x) і майже повні дуги, тони каталогу.
Розбіжність — не помилка сама: вона називає, що зміниться в читача, коли він перейде на модуль (здебільшого
дуга (x, x), яку читачі тримали то точкою, то всім колом, — дошка 11298). Код виходу 1 — лише коли модуль
суперечить сам собі (інваріанти нижче) чи копії розходяться поза названими класами.
Запуск із джерела/: python3 проби/колір_тон_дуги.py"""
import collections, math, random, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import колір_тон as Т
import колір_простір_перетворення as П
import palettes as PS
import verify as V
import палітра_запити as ПЗ
import фід_кадр_колір as ФКК


def дуги(rnd):
    """Дуги проби: цілі кінці, дробові, вироджені, майже повні, через 0°."""
    вихід = [(float(a), float(b)) for a in range(0, 360, 15) for b in range(0, 360, 15)]
    вихід += [(x, x) for x in (0.0, 0.4, 59.5, 180.0, 359.9)]
    вихід += [(10.5, 10.2), (70.3, 70.9), (359.6, 0.3), (0.0, 359.0), (1.0, 0.0)]
    вихід += [(round(rnd.uniform(0, 360), 3), round(rnd.uniform(0, 360), 3)) for _ in range(3000)]
    return вихід


def копія_середини(д):
    """`палітра_запити.py:128`, `палітра_гамут.py:82` (дошка 13201): (a + ((b − a) % 360)/2) % 360."""
    return (д[0] + ((д[1] - д[0]) % 360) / 2) % 360


def копія_точки(д, f):
    """`фід_добір.py:101` (дошка 13207): span = (b − a) % 360 or 360; (a + span·f) % 360."""
    span = (д[1] - д[0]) % 360 or 360
    return (д[0] + span * f) % 360


def копія_вкладеності(a, b):
    """`verify.вікно_всередині` (verify.py:1002, дошка 13207): (a0 − b0) % 360 + ширина a ≤ ширина b."""
    return (a[0] - b[0]) % 360 + (a[1] - a[0]) % 360 <= (b[1] - b[0]) % 360


def копія_пів(h, д):
    """Читач ч1 `колір_річ._на_дузі_пів` (дошка 13190): `in_arc` з верхнім краєм на один float нижче."""
    return Т.in_arc(h, (д[0], math.nextafter(д[1], -math.inf)))


def клас(д):
    """Клас дуги для звіту розбіжностей."""
    if д[0] == д[1]:
        return "(x, x)"
    if math.floor(д[0]) == math.floor(д[1]):
        return "кінці в одному градусі"
    return "інша"


def поділ(стара, нова, рівні):
    """Клас розбіжності на дугах з цілими кінцями: ті самі цілі градуси — копія лічить клітинками (щілина ≤ 1°
    між дугами зникає); стільки ж градусів, інші — з двох рівних кандидатів обрано інший; решта — «інша»."""
    if стара is None or нова is None:
        return "інша"
    г_с, г_н = Т.градуси_дуги(стара), Т.градуси_дуги(нова)
    if г_с == г_н:
        return "ті самі цілі градуси: копія лічить клітинками, щілина ≤ 1° зникає"
    return рівні + " — інший вибір" if len(г_с) == len(г_н) else "інша"


def головна():
    """Друкує звірку й інваріанти; код 1 — лише суперечність модуля."""
    rnd = random.Random(20261105)
    ДУГИ = дуги(rnd)
    КУТИ = [x / 4 for x in range(-1440, 1441)] + [-1e-17, 359.99999999999994, 360.0, 720.5]
    ТОНИ = [x / 10 for x in range(3600)]
    збої, розб = [], collections.Counter()

    # ── інваріанти модуля ──
    for к in КУТИ:
        н = Т.нормувати(к)
        if not 0.0 <= н < 360.0:
            збої.append(("нормувати", к, н))
    for a in ТОНИ[::7]:
        for b in ТОНИ[::11]:
            р, в = Т.різниця_на_колі(a, b), Т.відстань_тонів(a, b)
            if not (-180.0 <= р < 180.0 and abs(abs(р) - в) < 1e-9 and Т.відстань_тонів(b, a) == в):
                збої.append(("різниця/відстань", a, b, р, в))
    for д in ДУГИ:
        ш = Т.ширина_дуги(д)
        н = (Т.нормувати(д[0]), Т.нормувати(д[1]))
        for h in ТОНИ[::5]:
            if Т.in_arc(h, н) != (Т.зсув_за_ходом(н[0], h) <= ш + 1e-9 * (Т.зсув_за_ходом(н[0], h) == ш)):
                if abs(Т.зсув_за_ходом(н[0], h) - ш) > 1e-9:
                    збої.append(("in_arc ≠ зсув ≤ ширина", д, h))
        if set(Т.тони_дуги(д)) - {Т.нормувати(x) for x in Т.тони_дуги(д)}:
            збої.append(("тони_дуги поза [0, 360)", д))
        if not Т.дуга_в_дузі(д, д) or not Т.дуга_в_дузі(д, Т.ПОВНЕ_КОЛО):
            збої.append(("дуга_в_дузі сама в собі", д))
        if Т.перетин_дуг(д, д)[0] != (н if ш < 360 else Т.ПОВНЕ_КОЛО) and ш > 0:
            if abs(Т.ширина_дуги(Т.перетин_дуг(д, д)[0]) - ш) > 1e-9:
                збої.append(("перетин із собою", д, Т.перетин_дуг(д, д)))
    if not all(Т.in_arc(h, Т.ПОВНЕ_КОЛО) and Т.в_дузі_пів(h, Т.ПОВНЕ_КОЛО) for h in ТОНИ):
        збої.append(("ПОВНЕ_КОЛО не все коло",))
    if len(Т.градуси_дуги(Т.ПОВНЕ_КОЛО)) != 360 or len(Т.тони_дуги(Т.ПОВНЕ_КОЛО)) != 360:
        збої.append(("ПОВНЕ_КОЛО: градусів чи тонів не 360",))
    пари = [(ДУГИ[i], ДУГИ[(i * 7 + 3) % len(ДУГИ)]) for i in range(len(ДУГИ))]
    for a, b in пари:
        о = Т.об_єднати_дуги(a, b)
        if not (Т.дуга_в_дузі(a, о) and Т.дуга_в_дузі(b, о)):
            збої.append(("об'єднання не тримає обох", a, b, о))
        for ш in Т.перетин_дуг(a, b):
            if not (Т.дуга_в_дузі(ш, a) and Т.дуга_в_дузі(ш, b)):
                if not (Т.in_arc(ш[0], a) and Т.in_arc(ш[0], b)):
                    збої.append(("шматок перетину поза дугою", a, b, ш))

    # ── звірка з копіями читачів ──
    for a in ТОНИ[::3]:
        for b in ТОНИ[::13]:
            стара = (a - b + 180) % 360 - 180
            if Т.різниця_на_колі(a, b) != стара:
                розб["різниця_на_колі ≠ палітра_запити.py:78: " + (
                    "протилежні, копія дає 180 поза [−180, 180)" if стара == 180.0 else "інша")] += 1
            d = abs(a - b)
            if Т.відстань_тонів(a, b) != min(d, 360 - d):
                розб["відстань_тонів ≠ min(|d|, 360 − |d|) (surface.py:90)"] += 1
    for д in ДУГИ:
        к = клас(д)
        if Т.ширина_дуги(д) != (д[1] - д[0]) % 360:
            розб["ширина_дуги ≠ (b − a) % 360: " + к] += 1
        if abs(Т.середина_дуги(д) - копія_середини(д)) > 1e-9:
            розб["середина_дуги ≠ палітра_запити.py:128: " + к] += 1
        for f in (0.0, 0.25, 0.5, 1.0):
            if abs(Т.точка_дуги(д, f) - копія_точки(д, f)) > 1e-9:
                розб["точка_дуги ≠ фід_добір.py:101 («or 360»): " + к] += 1
        if Т.градуси_дуги(д) != PS._градуси_дуги(д):
            розб["градуси_дуги ≠ palettes._градуси_дуги: " + к] += 1
        for h in ТОНИ[::9]:
            if Т.в_дузі_пів(h, д) != копія_пів(h, д):
                розб["в_дузі_пів ≠ колір_річ._на_дузі_пів (ч1): " + к] += 1
        for доп in (0.0, 5.0, 30.0, 179.0, 180.0):
            стара, нова = V._дуга_з_допуском(д, доп), Т.розширити_дугу(д, доп)
            if стара is None:
                if нова != Т.ПОВНЕ_КОЛО:
                    розб["розширити_дугу: verify None, модуль не ПОВНЕ_КОЛО: " + к] += 1
            elif max(abs(Т.різниця_на_колі(x, y)) for x, y in zip(стара, нова)) > 1e-9:
                розб["розширити_дугу ≠ verify._дуга_з_допуском: " + к] += 1
    for a, b in пари:
        ка = клас(a) if клас(a) != "інша" else клас(b)
        if Т.дуга_в_дузі(a, b) != копія_вкладеності(a, b):
            розб["дуга_в_дузі ≠ verify.вікно_всередині: " + ка] += 1
        ціла_a, ціла_b = (float(int(a[0])), float(int(a[1]))), (float(int(b[0])), float(int(b[1])))
        стара = ПЗ.перетин_дуг(ціла_a, ціла_b)
        нові = Т.перетин_дуг(ціла_a, ціла_b)
        нова = None
        if нові:
            г = Т.градуси_дуги(нові[0])
            нова = (0.0, 359.0) if len(г) == 360 else нові[0]
        if стара != нова:
            ціла_к = клас(ціла_a) if клас(ціла_a) != "інша" else клас(ціла_b)
            if ціла_к == "інша":
                ціла_к = поділ(стара, нові[0] if нові else None, "рівні шматки")
                if ціла_к == "інша" and стара and len(нові) == 2 and Т.градуси_дуги(стара) == (
                        Т.градуси_дуги(нові[0]) | Т.градуси_дуги(нові[1])):
                    ціла_к = "ті самі цілі градуси: копія лічить клітинками, два шматки через щілину ≤ 1° злито"
            розб["перетин_дуг ≠ палітра_запити.перетин_дуг (цілі кінці): " + ціла_к] += 1
        вікно_а, вікно_б = (0, 1, 0, 1, ціла_a), (0, 1, 0, 1, ціла_b)
        стара = ФКК.вікно_з_кадром(вікно_а, вікно_б)[4]
        о = Т.об_єднати_дуги(ціла_a, ціла_b)
        нова = (0.0, 359.0) if о == Т.ПОВНЕ_КОЛО else о
        if стара != нова:
            ціла_к = клас(ціла_a) if клас(ціла_a) != "інша" else клас(ціла_b)
            if ціла_к == "інша":
                ціла_к = поділ(стара, о, "рівні щілини")
            розб["об_єднати_дуги ≠ фід_кадр_колір.вікно_з_кадром (цілі кінці): " + ціла_к] += 1
    for L in (20.0, 55.5, 90.0):
        for C in (0.0, 3.3, 41.7):
            for h in ТОНИ[::17]:
                if П.lab_з_lch(L, C, h) != PS.lab_з_lch(L, C, h):
                    розб["lab_з_lch ≠ palettes.lab_з_lch"] += 1
                if max(abs(x - y) for x, y in zip(П.lch(П.lab_з_lch(L, C, h))[:2], (L, C))) > 1e-9:
                    розб["lch(lab_з_lch) ≠ (L, C)"] += 1

    print("дуг проби: %d, пар: %d, кутів: %d, тонів: %d" % (len(ДУГИ), len(пари), len(КУТИ), len(ТОНИ)))
    print("інваріанти модуля — збоїв: %d" % len(збої))
    for з in збої[:10]:
        print("  ", з)
    print("розбіжності з копіями читачів (клас дуги після двокрапки):")
    for к, n in sorted(розб.items()):
        print("  %6d  %s" % (n, к))
    if not розб:
        print("  0")
    sys.exit(1 if збої or any(к.endswith(": інша") for к in розб) else 0)


if __name__ == "__main__":
    головна()
