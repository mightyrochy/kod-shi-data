# -*- coding: utf-8 -*-
"""Розбір 1/8, В-2 (вхід і сценарій): ТИПОВЕ ЗНАЧЕННЯ ФОРМИ ЙДЕ В ПАСПОРТ ЯК ЇЇ ФАКТ.
Друкує дефолти полів у `показ.html` (година, температура, зріст), рядок «обрано» в промпті
виклику 0 на НЕТОРКАНІЙ формі, поля паспорта з тієї ж форми й зріст із файла вердиктів власника.
ДО правки показ слав числа без походження, і вони стояли в «обрано», у паспорті й у рядку випадку;
ПІСЛЯ — показ називає неторкані поля (`сценарій.типові_поля`), код ставить їм мітку
`ТИПОВЕ_ПОЛЕ_ФОРМИ`, і жодна рука не чує їх як сказане. Запуск із теки `джерела`:
`python3 проби/шлях_вхід_типові_числа.py`."""
import sys, os, re, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import паспорт_нагоди as ПН

html = open("показ.html", encoding="utf-8").read()
for ід in ("сц-година", "сц-темп"):
    m = re.search(r'id="%s"[^>]*value="([^"]*)"' % ід, html) or re.search(r'value="([^"]*)"[^>]*id="%s"' % ід, html)
    print("показ.html: <input id=%s> дефолт value=%s" % (ід, m.group(1) if m else "—"))
m = re.search(r"const ТИПОВІ_ПОЛЯ_ВИПАДКУ = (\{[^}]*\})", html)
print("показ.html: ТИПОВІ_ПОЛЯ_ВИПАДКУ = %s" % m.group(1))
m = re.search(r"const ПОЛЯ_ТИПОВІ_ЧИСЛА = (\{[^}]*\})", html)
print("показ.html: ПОЛЯ_ТИПОВІ_ЧИСЛА = %s — перелік неторканих їде в `сценарій.типові_поля`"
      % (m.group(1) if m else "НЕМА (вада В-2 жива)"))
m = re.search(r"зріст: parseFloat\(\$\('мр-зріст'\)\.value\)\|\|(\w+)", html)
print("показ.html: `зібратиВхід` зріст = parseFloat(мр-зріст) || %s (було 167 — число коду)"
      % (m.group(1) if m else "?"))
print("показ.html: `чогоБракує` вимагає зросту: %s" % bool(re.search(r"\['мр-зріст','зріст'\]", html)))

# НЕТОРКАНА ФОРМА: рівно те, що показ шле у виклик 0
СЛОВА = "гуляю з собаками в парку, вітер"
ДО = {"нагода": "щоденне", "місце": "парк", "година": 11, "темп_c": 18}                                   # як показ слав доти
ПІСЛЯ = dict(ДО, типові_поля=["година", "темп_c"])                  # як показ шле тепер
for підпис, сц in (("ДО  (форма без походження)", ДО), ("ПІСЛЯ (показ назвав неторкані)", ПІСЛЯ)):
    промпт = json.loads(ПН.промпт_паспорта(сц, СЛОВА))
    п = ПН.паспорт_з_json("{}", сц, СЛОВА)
    тип = sorted(ПН.типові_з_форми(п))
    print("\n%s" % підпис)
    print("   виклик 0 (%d симв.): «обрано» = %s · «типове_не_назване» = %s"
          % (len(json.dumps(промпт, ensure_ascii=False)), json.dumps(промпт.get("обрано"), ensure_ascii=False),
             json.dumps(промпт.get("типове_не_назване"), ensure_ascii=False)))
    print("   паспорт: година=%s темп_c=%s · мітки «типове поле форми»: %s"
          % (п["година"], п["темп_c"], тип or "жодної"))
    print("   випадок для моделі: «%s»" % ПН.паспорт_рядком(п))
    print("   шапка жінці:        «%s»" % ПН.паспорт_рядком_людині(п))
    _теми = (ПН.порада_коду(сц, None, СЛОВА) or {}).get("теми") or []
    print("   теми поради цього ходу: %s — стилістка сама питає про градуси: %s"
          % (_теми or "жодної", "температура" in _теми))

ф = "../аудит/тести/власник_2026-09-25/verdykty-0phxvk-2026-09-25-2012.json"
д = json.load(open(ф, encoding="utf-8"))
print()
for пр in д["прогони"]:
    в = пр["спільне"].get("вхід_прогону") or {}
    if в:
        print("файл власника, розклад %s: мірки.зріст=%s (дефолт показу тоді — 167), сценарій=%s"
              % (пр["спільне"]["розклад"], (в.get("мірки") or {}).get("зріст"),
                 json.dumps({k: (в.get("сценарій") or {}).get(k) for k in ("година", "темп_c")}, ensure_ascii=False)))

п = ПН.паспорт_з_json("{}", ПІСЛЯ, СЛОВА)
assert ПН.типові_з_форми(п) == {"година", "темп_c"}, "мітка замовчування форми не стоїть"
assert "11:00" not in ПН.паспорт_рядком(п) and "18 °C" not in ПН.паспорт_рядком(п), \
    "замовчування форми досі їде в рядок випадку всіх чотирьох промптів"
_пр = json.loads(ПН.промпт_паспорта(ПІСЛЯ, СЛОВА, паспорт=п))
assert not ({"година", "темп_c"} & set(_пр.get("паспорт_досі") or {})), \
    "замовчування форми їде в модель ще й усередині «паспорт_досі» — без позначки"
_пр = json.loads(ПН.промпт_паспорта(ПІСЛЯ, СЛОВА))
assert not ({"година", "темп_c"} & set(_пр.get("обрано") or {})), \
    "замовчування форми досі стоїть у «обрано» промпта виклику 0 («що вона обрала плитками»)"
assert set(_пр.get("типове_не_назване") or {}) == {"година", "темп_c"}, \
    "замовчування форми їде в модель без позначки «вона цього не називала»"
assert "температура" not in ((ПН.порада_коду(ДО, None, СЛОВА) or {}).get("теми") or []), \
    "проба ДО зламалась: на формі без походження тема температури мала мовчати"
assert "температура" in ((ПН.порада_коду(ПІСЛЯ, None, СЛОВА) or {}).get("теми") or []), \
    "порада про температуру мовчить там, де жінка градусів не називала"
print("\nВ-2: замовчування форми як її факт — нема")
