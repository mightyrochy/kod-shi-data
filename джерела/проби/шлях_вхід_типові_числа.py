html = open("показ.html", encoding="utf-8").read()
for ід in ("сц-година", "сц-темп"):
    m = re.search(r'id="%s"[^>]*value="([^"]*)"' % ід, html) or re.search(r'value="([^"]*)"[^>]*id="%s"' % ід, html)
    print("показ.html: <input id=%s> дефолт value=%s" % (ід, m.group(1) if m else "—"))
m = re.search(r"const ТИПОВІ_ПОЛЯ_ВИПАДКУ = (\{[^}]*\})", html)
print("показ.html: ТИПОВІ_ПОЛЯ_ВИПАДКУ = %s — використано лише щоб СТАВИТИ значення (`застосуватиСценарій`)" % m.group(1))
m = re.search(r"зріст: parseFloat\(\$\('мр-зріст'\)\.value\)\|\|(\d+)", html)
print("показ.html: `зібратиВхід` зріст = parseFloat(мр-зріст) || %s — порожнє поле стає числом" % (m.group(1) if m else "?"))
print("показ.html: `чогоБракує` вимагає лише кольори + 4 обхвати + нагоду/слова — зросту в переліку нема")

