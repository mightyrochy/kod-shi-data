# -*- coding: utf-8 -*-
"""Рядок 163: свідки блиску біля обличчя на жалобі — ДО (другий свідок вимкнено) і ПІСЛЯ.
Похорон (`траур_випадку("траур", "похорон")`), каталог_повний: траурний пул (`траурне_відсічення`) і його
речі біля обличчя, у яких свідки блиску розходяться — крамниця (слово назви про саму річ або `волокно`)
каже шкіру, лак чи атлас, а фото (`матеріал_фото` + `блиск`) бачить іншу поверхню або, коли матеріал
блищить сам (атлас, лак), блиск нижче 2. Друкує, скільки таких у пулі, скільки знято з пулу, скільки
лишилось із «питанням» K-OCC-01 суду (`формальність.нагода_палітра` над самою річчю; верхній шар — у
стані «надворі», де його видно) і скільки мовчки.
Запуск: cd джерела && python3 проби/blysk_traur_163.py"""
import collections, json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as FK, траурний_регістр as ТР, формальність as ФМ, composer as КМ, outfit as O, fit as ПС
КАТ = FK._прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"]; ЗА_ІД = {r["id"]: r for r in КАТ}
вх = json.load(open("стенд_вх.json")); T = ПС.тіло(float(вх["зріст"]), {k: float(v) for k, v in вх["обхвати"].items()})
тр, справжні = ТР.траур_випадку("траур", "похорон"), ТР.свідки_блиску
def розбіжні(r):
    св = справжні(r); к, тк = ТР.клас_блиску(св["крамниця"])
    return ТР.біля_обличчя(r) and тк in ТР.ПОВЕРХНЯ_ЗА_ФОТО and (к or 0) >= 1 and (
        bool(св["фото"] and not св["згода"]) or (к >= ТР.БЛИСК_ГЛЯНЕЦЬ and (св["блиск"] or 0) < ТР.БЛИСК_ГЛЯНЕЦЬ))
def питання(r):
    річ = КМ._у_річ(dict(r), r["слот"], T)
    E = O.елементи([річ], стан="надворі" if r["слот"] == "верхній_шар" else "у_приміщенні")
    return [з["суть"] for з in ФМ.нагода_палітра(E, "траур", місце="похорон", речі=[річ])
            if з["правило"] == "K-OCC-01" and з.get("сила") == "питання" and "блиск" in з["суть"]]
розб = None
for мітка in ("ДО", "ПІСЛЯ"):
    ТР.свідки_блиску = справжні if мітка == "ПІСЛЯ" else (lambda r: dict(справжні(r), клас=None, розходяться=False))
    пул = {r["id"]: r for r in КАТ if not ТР.траурне_відсічення(r, тр)}
    розб = розб or [r for r in пул.values() if розбіжні(r)]      # ті самі речі — з пулу ДО
    знято = [r for r in розб if r["id"] not in пул]
    пит = {r["id"]: питання(r) for r in розб if r["id"] in пул}
    чим = collections.Counter(ТР.траурне_відсічення(r, тр) for r in знято)
    print("ФАКТ · %-5s траурний пул %d з %d · біля обличчя %d · свідки блиску розходяться: у пулі %d із %d (що були в пулі ДО), "
          "знято %d %s, «питання» K-OCC-01 %d, мовчки %d" % (мітка, len(пул), len(КАТ), sum(map(ТР.біля_обличчя, пул.values())),
          len(пит), len(розб), len(знято), dict(чим), sum(1 for v in пит.values() if v), sum(1 for v in пит.values() if not v)))
    for i, v in sorted(пит.items()) if мітка == "ПІСЛЯ" else ():
        print("        %s «%s» — %s" % (i, ЗА_ІД[i]["назва"][:40], v[0] if v else "мовчки"))
