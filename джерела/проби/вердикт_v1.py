# -*- coding: utf-8 -*-
"""Приймальна проба Т-03: вердикт коду — один обʼєкт ВЕРДИКТ_V1, промпт = той самий JSON.

Друкує ФАКТИ, а не «ок»: помилки схеми (має бути 0), скільки «[0.» і кодів правил у
промпті (0 і 0), скільки знахідок понад стелю категорії `outfit._КАТ_У_НП` (0), і
скільки K-KOH-05 у вердикті на футболка+джинси+кеди під cocktail (рівно 1: Н-P37).
Запуск: PYTHONPATH=. python3 проби/вердикт_v1.py
"""
import json, re
import bridge as B, outfit as O, протокол as P

вх = json.load(open("стенд_вх.json"))
d0 = dict(вх, сценарій=dict(нагода="вечірка", місце="ресторан", година=19, темп_c=18, дрес_код="cocktail"),
          випадок="коктейль, ресторан, 19:00")
p = json.loads(json.loads(B.виклик("запити", json.dumps(d0, ensure_ascii=False)))["руки"]["1"])
кат = B.каталог_останнього_пакета()
річ = lambda слот, рег: next(o["id"] for o in кат if o.get("слот") == слот and re.match(рег, str(o.get("назва") or ""), re.I))
понад = lambda вд: [(z["правило"], z["сила"], z["сила_нп"]) for о in вд["образи"] for z in о["знахідки"]
                    if O._КАТ_У_НП.get(z.get("сила")) is not None and z["сила_нп"] > O._КАТ_У_НП[z["сила"]]]
# 1) футболка + джинси + кеди під cocktail — одна знахідка K-KOH-05 на образ
в = json.loads(B.виклик("від_моделі", json.dumps(dict(d0, ід=[річ("верх", "футболк"), річ("низ", "джинс"), річ("взуття", "кед")]), ensure_ascii=False)))
зн = в["вердикт"]["образи"][0]["знахідки"]
print("cocktail футболка+джинси+кеди: знахідок %d, K-KOH-05 — %d, речей у ній %s, понад стелю %s, помилок схеми %d"
      % (len(зн), sum(z["правило"] == "K-KOH-05" for z in зн), [len(z["речі"]) for z in зн if z["правило"] == "K-KOH-05"],
         понад(в["вердикт"]), len(P.перевірити(P.СХЕМИ["ВЕРДИКТ_V1"], в["вердикт"]))))
# 2) стендова відповідь моделі: три образи ядра пулу і «потрібно»
ядро = lambda k: [p["пул"][с][k]["н"] for с in ("верх", "низ", "взуття", "сумка") if len(p["пул"].get(с) or []) > k]
текст = json.dumps(dict(образи=[dict(підпис="образ %d" % k, речі=ядро(k)) for k in range(3)], потрібно=["червоний шарф"]), ensure_ascii=False)
в = json.loads(B.виклик("від_моделі", json.dumps(dict(d0, текст_моделі=текст), ensure_ascii=False)))
вд, пр = в["вердикт"], в["промпт_ремонту"]
print("стенд: образів %d · знахідок по образах %s · помилок схеми %d · промпт %d символів · «[0.» %d · кодів правил %d · понад стелю %s"
      % (len(вд["образи"]), [len(о["знахідки"]) for о in вд["образи"]], len(P.перевірити(P.СХЕМИ["ВЕРДИКТ_V1"], вд)),
         len(пр), пр.count("[0."), len(re.findall(r"\b[KR]-[A-Z]{2,6}-\d{2}\b", пр)), понад(вд)))
print("   поля: %s · вітрина: %s · вимог %d · ід знахідок: %s"
      % (", ".join(вд), {с: len(v) for с, v in (вд.get("вітрина") or {}).items()}, len(вд["завдання"]["вимоги"]),
         [z["ід"] for z in вд["образи"][0]["знахідки"]][:4]))
