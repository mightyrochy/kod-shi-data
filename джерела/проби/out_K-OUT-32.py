"""K-OUT-32 (накинути — третій розвʼязок провалу драбини припусків).

ДО ПРАВКИ: знахідка йшла у відро `ремонти` `outer.ремонти`. `composer._оцінити`
свідомо не бере ремонт у СУМУ ШТРАФІВ (і правильно: комбінація з виходом не
має ранжуватись гірше) — але `зн` звідти було ЄДИНИМ джерелом вердикту, тож
разом із ключем ранжування воно вирішувало й те, про що система має право
сказати. Третій розвʼязок конфлікту припусків не бачив ніхто.
ПІСЛЯ: ремонти верхнього шару дописуються ПІСЛЯ `_оцінити` — ключ ранжування
не змінився, а рядок стоїть у `вердикт.образи[0].знахідки`."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, outer as OU

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
вх["сценарій"].update(темп_c=5, опади="ні")
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
к = з["кандидати"]
взяти = lambda сл, ум: next((кат[r["id"]] for r in (к.get(сл) or [])
                             if r["id"] in кат and ум(кат[r["id"]])), None)
пальто = взяти("верхній_шар", lambda c: c.get("тип_верхнього") in OU.ТРИМАЮТЬ_НАКИНУТИМ
               and c.get("рукав") != "реглан")
ід = [r["id"] for r in (пальто, взяти("сукня", lambda c: True),
                        взяти("взуття", lambda c: True)) if r]
print("верхній шар:", пальто["назва"][:56], "· тип", пальто.get("тип_верхнього"))
print("дозволені стани:", OU.стан([dict(пальто, слот="верхній_шар")], темп_c=5).get("дозволені"))
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
зн = ((вм.get("вердикт") or {}).get("образи") or [{}])[0].get("знахідки") or []
р = next((z for z in зн if z.get("правило") == "K-OUT-32"), None)
print("K-OUT-32 у вердикті:", "НЕМА" if not р else
      "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:58]))
print("речі рядка:", (р or {}).get("речі"))
