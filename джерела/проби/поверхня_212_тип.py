"""Аркуші поверхні: точка, інтервал і невідоме без вигаданого hex."""
import json
import os
import sys
sys.path.insert(0, os.path.dirname(__file__))
from поверхня_212 import споживачеві, колір_аркуша
from колір_річ import межі_кольору
from колір_звіту import підпис_кольору


def main():
    """Перевіряє межі, походження та відсутність плашки для невідомого кольору."""
    слово = споживачеві(None, ["синій"])
    межі = слово[1]["межі"]
    assert межі and межі[4] is not None and "hex" not in слово[1]
    запис = dict(слово="синій", колір_тип="інтервал", hex="#ffffff", lab=[100, 0, 0],
                 колір_не_вимір=dict(свідок="shop_word", вікно=(30, 50, 10, 20, (350, 10))))
    assert споживачеві(запис, ["синій"], True)[1]["межі"] == межі_кольору(запис)
    assert "350…10°" in підпис_кольору(запис)
    запис["колір_не_вимір"]["вікно"] = (45, 45, 12, 12, None)
    assert колір_аркуша(запис)["межі"] == (45, 45, 12, 12, None)
    assert колір_аркуша(dict(колір_тип="невідомо", hex="#ffffff")) is None
    assert підпис_кольору(dict(колір_тип="невідомо", hex="#ffffff")) == "невідомо"
    assert споживачеві(None, [])[1] is None
    assert isinstance(споживачеві(dict(колір_тип="невідомо", hex="#ffffff"), ["синій"])[1], dict)
    assert колір_аркуша(dict(слово="чорний", hex="#010203")) == "#010203"
    assert isinstance(колір_аркуша(dict(lab=[50, 0, 0])), str)
    поза = споживачеві(dict(слово="червоний", hex="#ff0000"), ["синій"])
    assert isinstance(поза[1], dict) and "поза вікном" in поза[2]
    print(json.dumps(dict(слово=слово, частковий=колір_аркуша(запис), поза=поза), ensure_ascii=False))


if __name__ == "__main__":
    main()
