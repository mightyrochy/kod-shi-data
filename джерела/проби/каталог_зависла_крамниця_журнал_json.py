"""Міряє сторінку 121 й відновлення частково обробленої збереженої сторінки."""
import tempfile
from pathlib import Path
from каталог_зависла_крамниця_json_проба import прогін, порція, РІЧ


def main():
    """Повторює незмінний каталог і обрив серед порції без повторного HTTP збережених сторінок."""
    помилок = 0
    for сім in ("woo", "shopify"):
        for частково in (False, True):
            with tempfile.TemporaryDirectory() as ж:
                запити = []
                def відповідь(контекст, адреса, **параметри):
                    """Повертає ту саму сторінку за тим самим номером."""
                    n = int(адреса.rsplit("=", 1)[1]); запити.append(n)
                    номери = ([1, 2, 3] if n == 1 else []) if частково else ([n] if n <= 121 else [])
                    return порція(сім, [dict(РІЧ, id=i, handle=f"p{i}", permalink=f"https://json.test/p{i}") for i in номери])
                до, _ = прогін(ж, сім, відповідь, стеля=1 if частково else 300)
                запити.clear()
                після, _ = прогін(ж, сім, відповідь)
                оч = [2] if частково else [121, 122]
                добре = запити == оч and int(після["готово"]) == (3 if частково else 121) and після["лишилось"] == "0"
                if частково:
                    файл = Path(ж) / "сирі/json.test.jsonl"
                    рядки = файл.read_bytes().splitlines(keepends=True); рядки[1] = b'\xd0\n'; файл.write_bytes(b''.join(рядки))
                    запити.clear(); відновлено, _ = прогін(ж, сім, відповідь)
                    добре &= запити == [] and відновлено["готово"] == "3" and відновлено["причина_код"] == "JOURNAL_CORRUPT"
                    _, зайві = прогін(ж, сім, відповідь); добре &= зайві == 0
                print(f"{сім}/частково={частково}: готово={до['готово']}->{після['готово']}, очікувані запити={оч}, добре={добре}")
                помилок += not добре
    return int(bool(помилок))


if __name__ == "__main__":
    raise SystemExit(main())
