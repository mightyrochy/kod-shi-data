# -*- coding: utf-8 -*-
"""Ф-1 (звіт Research П1, «поділ = плече + підбор − довжина»): куди каблук справді
входить, а куди ні. Друкує два факти: (1) K-FIT-03 «край проти опуклостей зон»
ІНВАРІАНТНИЙ до каблука — він підіймає тіло разом із подолом; (2) K-SIL-02 (поле
плечі–підлога) каблуком міняє вердикт, бо там опора — підлога.
Запуск із теки `джерела`: `python3 проби/фг1_каблук_поділ.py`."""
import os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import fit as ПС

т = ПС.тіло(158, {"плечі": 92, "груди": 90, "талія": 72, "стегна": 100})
H, ПЛ = т["висоти"], т["висоти"]["плечі"]
print("ТІЛО 158 см: плечі %.0f · стегна %.0f · коліно %.0f (см від підлоги)"
      % (ПЛ, H["стегна"], H["коліно"]))
пара = lambda к: dict(dict(id="пара", слот="взуття", тип="човники", верх_см=8.0, низ_см=0.0,
                           край_джерело="слово", халява_джерело="тип", халява_рівень=None),
                      **({"каблук_см": к} if к is not None else {}))

print("\n1) K-FIT-03 — КРАЙ ПРОТИ ОПУКЛОСТЕЙ: каблук тіло й поділ підіймає РАЗОМ")
жакет = dict(id="жакет", слот="верхній_шар", тип="жакет", верх_см=ПЛ, низ_см=H["стегна"],
             край_джерело="слово", крій="regular")
for каблук in (None, 7.0):
    зн = [з for з in ПС.краї(т, [жакет, пара(каблук)]) if з["правило"] == "K-FIT-03"]
    print("   каблук %-6s → знахідок %d: %s" % (каблук or "нема", len(зн),
          [(з["сила"], round(з["сила_нп"], 3), з["суть"][:32]) for з in зн]))
print("   підйом_взуття: %s | %s" % ПС.підйом_взуття([жакет, пара(7.0)]))
# ЩО БУЛО Б ЗА ДОСЛІВНИМ РЕЦЕПТОМ ЗВІТУ (підйом ЛИШЕ до краю, профіль на місці):
for край in (H["стегна"], H["стегна"] + 7.0):
    m = ПС.край_проти_локального(т["профіль"], край)
    print("   край %.0f см проти профілю: на максимумі=%s" % (край, m["на_максимумі"]))

print("\n2) K-SIL-02 — ПОЛЕ ПЛЕЧІ–ПІДЛОГА: опора підлога, і каблук міняє вердикт")
for лінія in (60.0, 65.0, 70.0):
    рядок = []
    for каблук in (None, 7.0):
        верх = dict(id="верх", слот="верх", верх_см=ПЛ, низ_см=лінія, край_джерело="слово")
        зн = ПС.поділ_образу(т, [верх, пара(каблук)])
        рядок.append("нема" if not зн else "сила_нп %.2f" % зн[0]["сила_нп"])
    print("   лінія речі %.0f см від підлоги: без каблука — %-12s у парі 7 см — %s"
          % (лінія, рядок[0], рядок[1]))
