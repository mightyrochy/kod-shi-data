"""Е3 з6: діагнози структури на повному каталозі й невдале складання шарів ДО → ПІСЛЯ."""
import collections, importlib, pathlib, subprocess, sys, types
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import feed as Ф
БАЗА = sys.argv[1] if len(sys.argv) > 1 else "0a57c69152e7dea68f951cb2bd61bf04152e4395"

def модуль(ім):
    """Завантажити код бази поруч із головою на тих самих даних."""
    м = types.ModuleType(ім + "_до")
    exec(subprocess.check_output(["git", "show", БАЗА + ":джерела/" + ім + ".py"]).decode("utf-8"), м.__dict__)
    return м, importlib.import_module(ім)

if __name__ == "__main__":
    до, після = модуль("суд_від_моделі")
    каталог = Ф.база_прогону(Ф.каталог_на_диску("каталог_повний.xml"), ліміт_фото=0)["каталог"]
    зміни = collections.Counter()
    ручні = [[dict(id="к", слот="комплект", склад_комплекту="верх"), dict(id="в", слот="верх")]]
    for речі in [[р] for р in каталог] + ручні:
        а, б = (м.структура_образу_заяви(речі) for м in (до, після))
        assert [x[0] for x in а[0]] == [x[0] for x in б[0]]
        assert а[1] == б[1]
        for (_, з), (_, н) in zip(а[0], б[0]):
            for д, п in zip(з, н):
                assert д["values"] == п["values"]
                if д["code"] != п["code"]: зміни[(д["code"], п["code"])] += 1
    річ = dict(id="к", слот="комплект", склад_комплекту="верх")
    а, б = [м.перевірити_від_моделі(["к"], {}, [річ], {}) for м in (до, після)]
    assert а["блокує"] == б["блокує"] and not а["перевірено"] and not б["перевірено"]
    print("Каталог:", len(каталог), "· ті самі блокери/м’які знахідки/значення; заяви:", dict(зміни))
    print("Одна річ:", а["заяви_блокерів"]["одна_річ"][0]["code"], "→", б["заяви_блокерів"]["одна_річ"][0]["code"])
    речі = [dict(id=с, слот=с) for с in ("верх", "низ", "взуття", "сумка", "прикраси", "верхній_шар")]
    о = dict(ід="о1", речі=[р["id"] for р in речі], структура=dict(ок=True, блокери=[]),
             знахідки=[dict(правило="K-OUT-06", регістр="гейт", сила="сильно", суть="layers conflict", речі=["верх", "верхній_шар"])])
    до, після = модуль("повнота_образу")
    for ремонт in (False, True):
        а, б = [м.повнота_набору(dict(образи=[о]), каталог=речі, кандидати={р["слот"]: [р] for р in речі},
                   дібрати=ремонт, суддя=lambda склади: [о for _ in склади]) for м in (до, після)]
        assert {к: в for к, в in а.items() if к != "рядок"} == {к: в for к, в in б.items() if к != "рядок"}
        print("Ремонт", ремонт, ":", [з["code"] for з in а["рядок"]["statements"]], "→", [з["code"] for з in б["рядок"]["statements"]])
    assert importlib.import_module("bridge")._змінна_пара({}, {}, [], {}, {})[0] is None
