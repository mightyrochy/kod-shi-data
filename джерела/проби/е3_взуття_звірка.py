"""Звірка двох знімків `е3_взуття_знімок.py`: склад і сила тотожні; зміни сирої й ефективної ваги за правилом."""
import collections, gzip, json, re, sys


def main():
    """Друк таблиці «правило · гілка · ДО · ПІСЛЯ · кількість» для сирих і ефективних змін ваги."""
    до, після = (json.load(gzip.open(ш, 'rt', encoding='utf-8')) for ш in sys.argv[1:3])
    assert len(до) == len(після), (len(до), len(після))
    сирі, еф, підлога, усього, поля = (collections.Counter() for _ in range(5))
    for д, п in zip(до, після):
        assert д[:6] == п[:6], (д, п)   # випадок, суддя, правило, суть, речі, сила
        гілка = (д[2], д[5], re.split(r'[\s:]', д[3])[0] if д[2] == 'K-SHO-07' else '')
        усього[гілка] += 1
        if д[6] != п[6]: сирі[гілка] += 1
        if д[7] != п[7]: еф[гілка + (д[7], п[7])] += 1
        if д[8] != п[8]: підлога[гілка + (д[8], п[8])] += 1
        if д[9] != п[9]: поля[гілка] += 1
    print('знахідок', len(до), '· склад, суть і сила тотожні · сирих змін', sum(сирі.values()),
          '· ефективних', sum(еф.values()), '· мітки підлоги', sum(підлога.values()),
          '· інших полів', sum(поля.values()))
    print('| правило · сила · гілка | знахідок | сирих змін | ефективних змін | інших полів |')
    print('|---|---|---|---|---|')
    for г in sorted(усього, key=str):
        print('| %s | %d | %d | %d | %d |' % (' · '.join(x for x in г if x), усього[г], сирі[г],
                                              sum(v for k, v in еф.items() if k[:3] == г), поля[г]))
    print('| правило · сила · гілка | ДО | ПІСЛЯ | кількість |')
    print('|---|---|---|---|')
    for k, v in sorted(еф.items(), key=str):
        print('| %s | %s | %s | %d |' % (' · '.join(x for x in k[:3] if x), k[3], k[4], v))
    print('мітки підлоги:', dict(підлога))


if __name__ == '__main__':
    main()
