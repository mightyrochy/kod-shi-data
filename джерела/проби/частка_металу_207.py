# -*- coding: utf-8 -*-
"""Проба (рядок 207): ЧИ Є В КОДІ ВХІД ПРО ПЛОЩУ МЕТАЛУ — покриття поля `частка_металу` на
всьому каталозі, розподіл частки й скільки речей вимір знімає з провідних (`суд_блиск.метали`).
Друкує факт, моделі не кличе. Запуск: python3 джерела/проби/частка_металу_207.py"""
import collections, os, sys                                                   # noqa: E401
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import фід_каталог as ФК, palettes as ПЛ, фід_збагачення as ФЗ                # noqa: E401,E402
записи = ФК._прочитати_каталог(ФК.каталог_на_диску(), ліміт_фото=0)["каталог"]
c, розп, нема = collections.Counter(), collections.Counter(), collections.Counter()
зб = ФЗ.читати_збагачення()
for r in записи:
    сл, м = r.get("слот"), r.get("метал")
    if not м or сл not in ПЛ.СЛОТИ_МЕТАЛУ:
        continue
    c["ювелірних_з_металом"] += 1
    ч = r.get("частка_металу")
    if ч is None:
        c["без_входу"] += 1
        з = зб.get(r.get("id"))
        нема["чуже_фото" if r.get("чуже_фото") else
             ("нема_збагачення_v2" if not (з and ФЗ._збагачення_придатне(з)
                                           and (з.get("версія") or 1) >= 2) else "інше")] += 1
        continue
    c["вхід_є"] += 1
    розп["0" if ч == 0 else ("<0.4" if ч < 0.4 else ("0.4-0.8" if ч < 0.8 else ">=0.8"))] += 1
print("ювелірних речей із названим металом %d · частку поверхні виміряно на %d (%d %%) · "
      "без входу %d" % (c["ювелірних_з_металом"], c["вхід_є"],
                        round(100 * c["вхід_є"] / (c["ювелірних_з_металом"] or 1)), c["без_входу"]))
print("чому без входу: %s" % ", ".join("%s %d" % t for t in нема.most_common()))
print("частка металу: %s" % ", ".join("%s %d" % t for t in розп.most_common()))
# ЩО З ЦЬОГО БАЧИТЬ СУД: річ із виміряним НУЛЕМ не може бути провідним металом образу
# (`суд_блиск.метали`, K-COL-06-M); річ БЕЗ виміру важить як доти (мовчання ≠ нуль, K-IO-04)
import суд_блиск as СБ                                                        # noqa: E402
E = [dict(річ="обруч з обідком", метал="золото", near=0.95, площа=0.05, частка_металу=0.0),
     dict(річ="каблучка суцільна", метал="золото", near=0.30, площа=0.01, частка_металу=0.62)]
зн = СБ.метали(E, {}, прикраси="срібло")
вед = [z for z in зн if z.get("правило") == "K-COL-06-M"]
print("ведучий метал на парі «обруч біля обличчя (0.0) + каблучка (0.62)»: %s"
      % (вед[0]["речі"][0] if вед and вед[0].get("речі") else "знахідки нема"))
