# -*- coding: utf-8 -*-
"""Приймальна проба Т-04: відповідь моделі — ОБРАЗИ_V1, оголошені ходи з поля «свідомо».

Друкує ФАКТИ, а не «ок»: силу K-KOH-06 над сукнею й мітку `свідомий` — без
оголошення і з ним (×0.6: 0.45 → 0.27), на ВЕРХНЬОМУ рівні `від_моделі` і в образі
вердикту, при ОДНОМУ образі й при ДВОХ (де оголошення стоїть лише над першим і не
має права послабити другий). До правки Т-04 всі три рядки однакові: 0.45 без мітки й
без жодного оголошення — на JSON-шляху `свідомі` були порожні завжди (V33).
Запуск із теки `джерела`: PYTHONPATH=. python3 проби/образи_v1.py
"""
import json, os, tempfile
import bridge as B, feed as Ф, протокол as P

вх = json.load(open("стенд_вх.json", encoding="utf-8"))
d0 = dict(вх, каталог=Ф.каталог_на_диску("каталог_brief.xml"), варіантів=10, ремонт_варіантів=5,
          кеш_кольорів=os.path.join(tempfile.gettempdir(), "кеш_проби_т04.json"))
пул = json.loads(json.loads(B.виклик("запити", json.dumps(d0, ensure_ascii=False)))["руки"]["1"])["пул"]
сукні, вз = [r["н"] for r in пул["сукня"]], пул["взуття"][0]["н"]
сила = lambda зн: [(z["сила_нп"], bool(z.get("свідомий"))) for z in зн if z.get("правило") == "K-KOH-06"]

def прогін(образи):
    т = json.dumps(dict(версія="1", образи=образи), ensure_ascii=False)
    в = json.loads(B.виклик("від_моделі", json.dumps(dict(d0, текст_моделі=т), ensure_ascii=False)))
    return ("K-KOH-06 верху (сила, свідомий) %s · оголошення верху (річ → ід, послаблено) %s"
            " · по образах %s · помилок схеми вердикту %d"
            % (сила(в.get("знахідки") or []),
               [(с.get("річ"), с.get("ід"), с.get("послаблено")) for с in (в.get("свідомі") or [])],
               [(о["ід"], сила(о["знахідки"])) for о in в["вердикт"]["образи"]],
               len(P.перевірити(P.СХЕМИ["ВЕРДИКТ_V1"], в["вердикт"]))))

о1 = lambda оголошення: dict(ід="о1", підпис="вечірній тон", речі=[сукні[3], вз], **оголошення)
хід = dict(свідомо=[dict(річ=сукні[3], чому="світлий тон узятий навмисно, це задум образу")])
print("один образ, без оголошення: %s" % прогін([о1({})]))
print("один образ, «свідомо»:      %s" % прогін([о1(хід)]))
print("два образи, «свідомо» в о1: %s" % прогін([о1(хід), dict(ід="о2", підпис="інша сукня", речі=[сукні[4], вз])]))
