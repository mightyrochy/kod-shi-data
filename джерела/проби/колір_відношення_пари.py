"""КОЛІР-Р4 (рядок 2694, хвиля 1): вердикти відношень кольору на тих самих парах, що в рядках 2693 і 2695, — 4 сцени
стенда (`колір_опори_до_після.py`, #715), «гучний одяг × гучний аксесуар» з кандидатів (C* ≥ 40, `АС._C_речі`), усі
пари й пари ОДНОГО слова кольору. «same_hue» — той самий сектор кола художника (±15°, рішення Р2а): ДО — `відлуння_тону`
КОЛІР-Р2, ПІСЛЯ — `колір_річ.відношення(a, b, "same_hue")`; лічба переходів «так/ні/невідомо» (має бути без змін). ПІСЛЯ —
ще розподіл кожного класу API (`КЛАСИ_ВІДНОШЕНЬ`) на тих самих парах і свідки кодом (`запис_кольору`).
Запуск із джерела/: python3 проби/колір_відношення_пари.py"""
import json, sys, collections as K; sys.path.insert(0, ".")
import bridge as B, стенд_знімок as СЗ, колір_річ as КР, аксесуари_структура as АС
вх0 = json.load(open("стенд_вх.json", encoding="utf-8")); АПІ = hasattr(КР, "відношення")
тон = (lambda a, b: КР.відношення(a, b, "same_hue")) if АПІ else КР.відлуння_тону
гучна = lambda x: (АС._C_речі(x) or 0.0) >= 40; Л, КЛ, СВ = K.Counter(), K.Counter(), K.Counter()
for назва in ("офіс·18°C", "дощ·ресторан·вечір", "весілля·гість", "спека·парк"):
    к = json.loads(B.виклик("запити", json.dumps(dict(вх0, сценарій=dict(СЗ.СЦЕНАРІЇ[назва]), випадок=назва), ensure_ascii=False)))["кандидати"]
    зі = {r["id"]: r for r in B.каталог_останнього_пакета()}
    г = [(с, r["id"]) for с, рр in к.items() for r in рр if гучна(зі.get(r["id"]) or {})]
    for a, b in [(x, y) for с1, x in г for с2, y in г if с1 not in АС.СЛОТИ_АКСЕСУАРІВ and с2 in АС.СЛОТИ_АКСЕСУАРІВ]:
        x, y = зі[a], зі[b]; гр = ("усі", "одне слово") if x.get("колір_ім") and x.get("колір_ім") == y.get("колір_ім") else ("усі",)
        v = тон(y, x)
        for g in гр: Л["%-10s тон: %s" % (g, v)] += 1
        if not АПІ: continue
        assert v == КР.відношення(x, y, "same_hue"), (a, b)   # симетрія
        for кл, вв in КР.відношення(y, x).items(): КЛ["%-15s %s" % (кл, вв)] += 1
        for r in (x, y): СВ[КР.запис_кольору(r)["свідок"]] += 1
print("API:", "так" if АПІ else "ні (ДО — КОЛІР-Р2)")
for к_, v in sorted(Л.items()): print("  %-28s %5d" % (к_, v))
for к_, v in sorted(КЛ.items()): print("  клас %-26s %5d" % (к_, v))
if СВ: print("  свідки (з повторами):", dict(СВ))
