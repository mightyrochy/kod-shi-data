# -*- coding: utf-8 -*-
"""K-PAL-05 (приглушена комплементарна) — умова прийому судить образ.

Корпус (тема-2:1851): «сім'я + її комплемент, один із двох приглушений або малий;
середній/високий контраст; НА М'ЯКІЙ ЛЮДИНІ — ОБИДВА ПРИГЛУШЕНІ» (K-COL-03,
бюджет хроми). Умова жила в полі `коли` словника `ПРИЙОМИ`: вона не вмикала
нічого (доступність рахувалась лише для трьох прийомів із дванадцяти) і нікого не
судила.
ПІСЛЯ — два місця: `palettes.прийоми` знімає прийом на низькому контрасті (список
доступних прийомів їде в пакет, тож різниця вже не косметична), а
`pipeline.палітра_образу` рахує гучні кольори комплементарної пари проти
дозволених — нуль на м'якій людині, один інакше.
Запуск із теки `джерела`: `python3 проби/pal_K-PAL-05.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import pipeline as PL, реєстр_правил as РП

вх, r, кат, спец = ПВ.стенд(гілка=0, намір="statement")
П = спец["палітра_практична"]
м_яка = П["осі"]["позиція"]["chroma"] < 0
гучно = РП.C["hi_C"]
акт = {x["прийом"] for x in П["прийоми"] if x["активний"]}
print("вісь ясності %+.2f → палітра %s · контраст «%s» → прийом доступний: %s · гучних "
      "дозволено %d (поріг хроми %.0f)"
      % (П["осі"]["позиція"]["chroma"], "м'яка" if м_яка else "не м'яка", П["контраст_рівень"],
         "приглушена_комплементарна" in акт, 0 if м_яка else 1, гучно))
гучний = lambda L, C, h, з: not PL._нейтральний_тон(h, C, L) and C >= гучно
верх = ПВ.з_каталогу(кат, "верх", гучний)
h1 = ПВ.lch(кат, верх["id"])[2] if верх else 0.0
низ = ПВ.з_каталогу(кат, "низ", lambda L, C, h, з: гучний(L, C, h, з)
                    and abs((h - h1 + 180) % 360 - 180) >= 150)
решта = [ПВ.взяти(r, кат, с, lambda *a: True) for с in ("взуття", "сумка")]
if not (верх and низ):
    print("ФАКТ · гучної комплементарної пари нема в усьому каталозі — судити нема що")
    raise SystemExit(0)
print("пара з каталогу: %s h%.0f C%.0f + %s h%.0f C%.0f"
      % ((верх["назва"] or "")[:20], h1, ПВ.lch(кат, верх["id"])[1],
         (низ["назва"] or "")[:20], ПВ.lch(кат, низ["id"])[2], ПВ.lch(кат, низ["id"])[1]))
зн, _ = ПВ.знахідки(вх, [x["id"] for x in [верх, низ] + [y for y in решта if y]][:4])
print("ФАКТ · K-PAL-05: %s" % ПВ.рядок(зн, "K-PAL-05"))
z = next((x for x in зн if x.get("правило") == "K-PAL-05"), None)
assert z and z["сила"] == "default", z
print("       ремонт: %s" % z["ремонт"])
