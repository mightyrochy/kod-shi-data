# -*- coding: utf-8 -*-
"""П-7 читає злитий стан перекладу (3.4-Ж, вада 9859): ДО — останній запис шару, ПІСЛЯ — усі записи `palette*`.

Вхід — збережені відповіді живого 3.4-А С2 `02_ж5_свято_др` (`seed3_07` — основний виклик: 12 заяв, переклав 10;
`seed3_08` — дозапит `palette.retry` двох заяв `рідша.0`). Умову очікування П-7 беремо з самого
`аудит/проби/рв6_стенд.js` (ПІСЛЯ — з робочого файлу, ДО — з аргументу `--до <файл>`) і виконуємо в `node` над записами,
які `джерела/показ/мовний_шар.js:повідомленнямМоделлюП` складає з цих відповідей. Живого прогону нема.
Запуск: `python3 джерела/проби/п7_злитий_стан.py <seed3_07> <seed3_08> <стенд_ДО.js>`."""
import sys, re, json, subprocess, pathlib

def відповідь(шлях):
    с = pathlib.Path(шлях).read_text(encoding='utf-8')
    заяви = json.loads(re.search(r'ПОВІДОМЛЕННЯ:\n(.*?)\n\n── ВІДПОВІДЬ', с, re.S).group(1))
    пер = json.loads(re.search(r'── ВІДПОВІДЬ.*?```json\n(.*?)```', с, re.S).group(1))
    return заяви, пер

def умова(js):
    м = re.search(r"'відповідь стилістки П-7 на екрані «Палітра»[^']*', \(\) => \{\n(.*?)\n    \}, null, 600000\)", js, re.S)
    assert м, 'умова П-7 не знайдена'
    return м.group(1)

осн, пер1 = відповідь(sys.argv[1])
повтор, пер2 = відповідь(sys.argv[2])
assert len(осн) == 12 and len(пер1) == 10 and {з['key'] for з in повтор} <= set(осн_к['key'] for осн_к in осн)
ключі_повтору = [з['key'] for з in повтор]
# основний виклик: 9 заяв — `пал-стан`, 1 — `пал-нота`, 2 пропущені — `рідша.0`; дозапит — лише `рідша.0`
пов = lambda з: {'kind': 'palette', 'statements': з}
осн_вхід = {'пал-стан': пов(осн[:9]), 'пал-нота': пов(осн[9:10]), 'рідша.0': пов(осн[10:])}
записи = [
    {'де': 'palette', 'вхід': осн_вхід, 'заяви': [{'повідомлення': 'пал-стан', 'заяви': осн[:9]}, {'повідомлення': 'пал-нота', 'заяви': осн[9:10]}, {'повідомлення': 'рідша.0', 'заяви': []}]},
    {'де': 'palette.retry', 'вхід': {'рідша.0': пов(повтор)}, 'заяви': [{'повідомлення': 'рідша.0', 'заяви': повтор}]},
]
assert [з['key'] for з in осн[10:]] == ключі_повтору
стенд = {'ПАСПОРТ_П': True, 'ВИБІР': {'гілка': 0, 'вибір_кольору': {}}, 'ПАЛ_МОВА_ШАРУ': записи,
         'ОСТАННЯ_ДІЯ_П': {'назва': 'палітра'}, 'стилісткаПалітриП': {'стан': 'обрала'}}
скрипт = """
const g = JSON.parse(require('fs').readFileSync(0, 'utf8'));
const тіло = g.умова;
const ф = new Function('ПАСПОРТ_П', 'ВИБІР', 'ПАЛ_МОВА_ШАРУ', 'ОСТАННЯ_ДІЯ_П', 'стилісткаПалітриП',
  'return (() => {' + тіло + '})()');
process.stdout.write(String(ф(g.ПАСПОРТ_П, g.ВИБІР, g.ПАЛ_МОВА_ШАРУ, g.ОСТАННЯ_ДІЯ_П, () => g.ст)));
"""
рез = {}
for назва, js in (('ДО', pathlib.Path(sys.argv[3]).read_text(encoding='utf-8')),
                  ('ПІСЛЯ', pathlib.Path(__file__).resolve().parents[2].joinpath('аудит/проби/рв6_стенд.js').read_text(encoding='utf-8'))):
    вх = dict(стенд, умова=умова(js), ст=стенд['стилісткаПалітриП'])
    рез[назва] = subprocess.run(['node', '-e', скрипт], input=json.dumps(вх), capture_output=True, text=True, check=True).stdout
    print(f'П-7 {назва}: {рез[назва]}')
sys.exit(0 if (рез['ДО'], рез['ПІСЛЯ']) == ('false', 'true') else 1)
