/* Доповнення рядка 210: «Речей на картинці: 8 з 8» — число про ФОТО, не про намальоване.
   Тестувальниця (ComfyUI, сід 13, рука 2; знімки `prymirka_kadr_comfyui_seed13.jpg` і
   `prymirka_kartka_ruka2_seed13.jpg`): на картці «8 з 8», на кадрі намальовано ТРИ речі
   (кардиган, джинси, чоботи; пальта, сумки, паска, обруча нема). `дійшло()` рахує
   `x-images-dropped` — скільки фото дійшло до моделі, і нічого більше.
   Проба бере вираз `рядокРечей` ДО (origin/main) і ПІСЛЯ (робоче дерево) і друкує рядок
   на числах того самого прогону. Запуск із теки `джерела`: node проби/kadr_richei_210.js */
const fs = require("fs"), { execFileSync } = require("child_process");
const ВИТЯГ = /const рядокРечей = \([\s\S]*?ілюстрація\.'\);/;
function рядок(html, мітка, п) {
  const m = html.match(ВИТЯГ);
  if (!m) throw new Error("не знайдено `рядокРечей` у " + мітка);
  const тіло = m[0].replace(/^const рядокРечей = /, "return (").replace(/;$/, ");");
  return new Function("режимП", "к", "бракує", "недоїхало", "єЩоКупити", тіло)(
    п.режимП, п.к, п.бракує, п.недоїхало, п.єЩоКупити);
}
const main = execFileSync("git", ["show", "origin/main:джерела/показ.html"], { encoding: "utf8" }),
      тут = fs.readFileSync(__dirname + "/../показ.html", "utf8");
/* Прогін тестувальниці: рука 2, вісім речей каталогу, усі фото дійшли, намальовано три. */
const ПРОГОНИ = [
  { мітка: "сід 13, рука 2 — усі фото дійшли (намальовано 3)", режимП: "за фото",
    к: { примірка: { речей: 8, всього: 8, з: 8, без_фото: [] } }, бракує: [], недоїхало: 0 },
  { мітка: "два знімки крамниця не віддала", режимП: "за фото",
    к: { примірка: { речей: 6, всього: 8, з: 8, без_фото: [] } }, бракує: [], недоїхало: 2 },
  { мітка: "рука 3 — за описом, каталогу нема", режимП: "за описом",
    к: { примірка: { речей: 0, всього: 0, з: 0, без_фото: [] } }, бракує: [], недоїхало: 0 },
];
const ОБІЦЯНКА = /Речей на картинці/;
let до = 0, після = 0;
for (const п of ПРОГОНИ) {
  const дод = { єЩоКупити: п.режимП === "за фото" };
  const d = рядок(main, "origin/main", { ...п, ...дод });
  const a = рядок(тут, "робоче дерево", { ...п, ...дод });
  до += ОБІЦЯНКА.test(d); після += ОБІЦЯНКА.test(a);
  const мітка = р => ОБІЦЯНКА.test(р) ? "\n         ← обіцяє намальоване, якого код не міряв" : "";
  console.log("%s\n   ДО    %s%s\n   ПІСЛЯ %s%s", п.мітка, d, мітка(d), a, мітка(a));
}
console.log("рядків, що обіцяють намальоване: ДО %d з %d → ПІСЛЯ %d з %d", до, ПРОГОНИ.length, після, ПРОГОНИ.length);
console.log("ПІСЛЯ каже, чого код не міряв: %s",
  рядок(тут, "т", { ...ПРОГОНИ[0], єЩоКупити: true }).includes("код не міряв") ? "так" : "НІ");
