"""Порівнює траурний відсів на всьому каталозі з кодом бази наряду; моделі не викликає."""
import collections, itertools, os, subprocess, sys, types
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed, траурний_регістр as Т
def головна():
    """Лічити причини й назвати кожну змінену річ для чотирьох виборів прикрас."""
    база = sys.argv[1] if len(sys.argv) > 1 else "a2bdf3df08ed3076d9e661f13ef27be8e84614d2"
    старий = types.ModuleType("траур_до")
    текст = subprocess.check_output(["git", "show", база + ":джерела/траурний_регістр.py"]).decode("utf-8")
    exec(compile(текст, "траур_до.py", "exec"), старий.__dict__)
    каталог = feed._прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"]
    print("база", база, "речей", len(каталог), flush=True)
    for вибір in ("невідомо", "перли", "срібло", "золото"):
        тр = Т.траур_сцени(dict(нагода="траур", місце="похорон", прикраси=вибір))
        до, після, зміни = collections.Counter(), collections.Counter(), []
        for р in каталог:
            а, б = старий.траурне_відсічення(р, тр), Т.траурне_відсічення(р, тр)
            до[а or "допущено"] += 1
            після[б or "допущено"] += 1
            if а != б:
                зміни.append((р["id"], а, б))
        print(вибір, "ДО", dict(до), "ПІСЛЯ", dict(після), "зміни", зміни, flush=True)
    всього, відмінних, вад = 0, 0, 0
    for слот, місце, візерунок, блиск, метал, вибір in itertools.product(
            ("верх", "сережки", "прикраси", "головний_убір", "браслет", "взуття"), (None, "так", "ні"),
            (None, *Т.ГУЧНІ_ВІЗЕРУНКИ_ТРАУРУ), (0, 1, 2, 3), (None, "gold"), ("невідомо", "золото")):
        р = dict(id="р", слот=слот, тип="блуза" if слот == "верх" else "headband", візерунок=візерунок, блиск=блиск, метал=метал)
        if місце:
            р["місце_стилістки"] = dict(біля_обличчя=місце)
        тр = Т.траур_сцени(dict(нагода="траур", місце="похорон", прикраси=вибір))
        а, б = старий.траурне_відсічення(р, тр), Т.траурне_відсічення(р, тр)
        всього += 1
        відмінних += а != б
        вад += а != б and not (а == "mourning_metal_near_face_not_chosen" and Т.не_несе_металу_прикраси(р) and б is None)
    print("комбінацій", всього, "відмінностей фурнітури", відмінних, "вад", вад, flush=True)
    return bool(вад)
if __name__ == "__main__":
    sys.exit(головна())
