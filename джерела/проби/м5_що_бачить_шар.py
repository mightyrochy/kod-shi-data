"""М-5: що бачить мовна модель на ходу 3 розмови, де «ні, краще темніше» відсилає до ходу 1.
«До» — перекладач входу (`промпт_входу`) і сторож цитат лише на словах ходу; «після» — хід розмови
(`промпт_розмови`) і сторож на всіх її репліках. Друкує факт. Запуск: cd джерела && python3 проби/м5_що_бачить_шар.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import мовний_шар as М
ходи = ["На побачення в ресторан у суботу, хочу бежеву сукню", "Люблю класику", "Ні, краще темніше"]
до = М.промпт_входу("scenario", ходи[2], {"offered_topics": ["goal", "makeup", "jewelry"]})
п1 = json.loads(М.мова({"паспорт_з": {"occasion": "date", "wants": [{"slot": "dress", "color_name": "beige",
                         "quote": "хочу бежеву сукню"}], "quotes": {"occasion": "На побачення"}},
                         "сценарій": {}, "слова_ходу": ходи[0]}))["паспорт"]
історія = [{"хто": "людина", "текст": ходи[0]}, {"хто": "ші", "текст": "Записала."}, {"хто": "людина", "текст": ходи[1]}]
після = М.промпт_розмови({"розмова": {"нове": ходи[2], "історія": історія}, "сценарій": {}, "паспорт": п1})
for назва, п in (("ДО   (перекладач входу)", до), ("ПІСЛЯ (хід розмови)", після)):
    print("%s: символів %d · хід 1 у промпті: %s · бежева сукня з паспорта: %s · хід 2: %s"
          % (назва, len(п), ходи[0] in п, '"color_name": "beige"' in п, ходи[1] in п))
# сторож: «ні, краще темніше» знімає бежеву сукню — уривок стоїть у ході 1
в = {"retract": [{"slot": "dress", "color_name": "beige", "quote": "хочу бежеву сукню"}],
     "wants": [{"slot": "dress", "color_class": "dark", "quote": "краще темніше"}]}
for назва, слова in (("ДО   сторож на словах ходу", ходи[2]), ("ПІСЛЯ сторож на всіх її репліках", [ходи[0], ходи[1], ходи[2]])):
    ш = json.loads(М.мова({"паспорт_з": в, "сценарій": {}, "паспорт": п1, "слова_розмови" if isinstance(слова, list)
                           else "слова_ходу": слова}))
    print("%s: %s · вигадок %d" % (назва, ш["випадок_людині"], len(ш["вигадки"])))
ок = ходи[0] in після and ходи[0] not in до
print("✓ модель розмови бачить попередні ходи й паспорт" if ок else "✗ попередніх ходів у промпті розмови нема")
sys.exit(0 if ок else 1)
