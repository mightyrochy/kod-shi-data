# -*- coding: utf-8 -*-
"""Рядок 2140: чи міряє траурний регістр колір ювелірної речі без металу поза слотом «прикраси»
(брошка-троянда «Ната пудра» ж-07631, живий С5 «Третій образ»). Каталог_повний, похорон, `прикраси`
«срібло» — ДО (`_прикраса_кольором` вимкнено) і ПІСЛЯ. Друкує: пул, скільки таких речей лишилось і
де ж-07631, ж-07623 (чорна брошка — має лишитись) і ж-11741 (каблучка з білого золота — метал її
вибору, регістр метал не міряє, п.9). Запуск: cd джерела && python3 проби/traur_prykrasa_2140.py"""
import collections, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as FK, траурний_регістр as ТР
КАТ = FK._прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"]
за_ід = {r["id"].split("@")[0]: r for r in КАТ}
справжня = ТР._прикраса_кольором
тр = ТР.траур_сцени(dict(нагода="траур", місце="похорон", прикраси="срібло"))
for мітка in ("ДО", "ПІСЛЯ"):
    ТР._прикраса_кольором = справжня if мітка == "ПІСЛЯ" else (lambda r: False)
    пул = [r for r in КАТ if not ТР.траурне_відсічення(r, тр)]
    без = [r for r in пул if r.get("слот") in feed._МЕТАЛ_СЛОТИ and r["слот"] != "прикраси" and not r.get("метал")]
    print("ФАКТ · %-5s пул %d · ювелірних без металу поза «прикраси» %d %s" % (
        мітка, len(пул), len(без), dict(collections.Counter(r["слот"] for r in без))))
    for і in ("ж-07631", "ж-07623", "ж-11741"):
        print("        %s %-34s %s" % (і, (за_ід[і].get("назва_показу") or за_ід[і]["назва"])[:34],
              ТР.траурне_відсічення(за_ід[і], тр) or "у пулі"))
ТР._прикраса_кольором = справжня
