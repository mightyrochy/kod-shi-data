"""Ділянка 8: КОЖНА РІЧ ОКРЕМО ПРОТИ ОБРАЗУ РАЗОМ. П'ять речей із запису 26.09 (жакет, сорочка,
міні, клатч, ботильйони) прогнано (1) тим, що справді робить розмова — `річ_з_фото.вердикт` на
КОЖНУ річ окремо, і (2) тим, чого розмова не кличе, — `pipeline.перевірити_образ` на ті самі
п'ять як на ОДИН образ. Друкує рядки жінці, знахідки кожного шляху й знахідки ПРО ПОЄДНАННЯ.
Запуск із `джерела`: python3 проби/шлях_оцінка_окремо.py"""
import sys, json; sys.path.insert(0, '.')
import річ_з_фото as РФ, composer as КМ, pipeline as PL, colorspace as cs, колір_образу as КО
from міст_вхід import _збірка, _нормалізувати_вхід
вх = json.load(open('стенд_вх.json')); F, T, _з, _к = _збірка(_нормалізувати_вхід(dict(вх)))
ОБРАЗ = [('ф1', 'жакет приталений', 'верхній_шар', '#7d7f63', 'хакі', 6),
         ('ф2', 'сорочка з драпуванням', 'верх', '#cfd8e3', 'блакитний', 5),
         ('ф3', 'шкіряна міні-спідниця трапеція', 'низ', '#6b1f2a', 'бордовий', 6),
         ('ф4', 'клатч плетіння', 'сумка', '#7a2230', 'бордовий', 6),
         ('ф5', 'ботильйони на підборах', 'взуття', '#e6dfd2', 'вершковий', 6)]
СЦЕН = dict(нагода='щоденне', місце='зал', година=11, темп_c=18)   # картка з запису: «11:00, +18 °C»
записи = [dict(ід=і, фото=і, назва=н, слот=с, колір=к, ошатність=о, чия='моя',
               вимір=dict(lab=list(cs.hx(h)), hex=h, слово=к)) for і, н, с, h, к, о in ОБРАЗ]
окремо, зн_окремо = [], 0
for р in записи:
    в = РФ.вердикт(р, F, T, СЦЕН, типова_нагода=True)
    зн_окремо += len(в['знахідки']); окремо.append((р['назва'], в['рівень'], в['рядок']))
print('ШЛЯХ РОЗМОВИ — %d окремих вердиктів, знахідок разом %d:' % (len(окремо), зн_окремо))
for н, рів, ряд in окремо:
    print('  «%s» — %s | %s' % (н, рів, ряд))
пар = len(записи) * (len(записи) - 1) // 2
print('  знахідок ПРО ПОЄДНАННЯ речей між собою (%d можливих пар): 0 — `вердикт` бачить одну річ' % пар)
речі = [КМ._у_річ(РФ.запис_каталогу(р), р['слот'], T) for р in записи]
рез = PL.перевірити_образ(F, речі, тіло=T, **СЦЕН)
зн = [з for ст in рез['стани'].values() for з in ст]
зн += [з for з in (рез.get('особа') or []) if isinstance(з, dict)]
зн = list({(з.get('правило'), з.get('суть')): з for з in зн if isinstance(з, dict)}.values())
міжречові = [з for з in зн if len(з.get('речі') or []) > 1]
print('СУД ОБРАЗУ на тих самих п\'яти: знахідок %d, із них про кілька речей одразу %d'
      % (len(зн), len(міжречові)))
for з in зн:
    print('  %-10s %-9s речей %d | %s' % (з.get('правило') or '—', з.get('сила') or '—',
                                          len(з.get('речі') or []), str(з.get('суть'))[:80]))
print('площозалежних правил кольору утримано без площ: %d; → те, що відповідає на «чи поєднуються ці'
      ' кольори між собою», рахується, але в розмову не йде: `перевірити_образ` кличе лише ендпойнт'
      ' `від_моделі` (після «Зібрати образи»)' % len(КО.ПЛОЩОЗАЛЕЖНІ_ІД))
