    assert П.злам('K-KOH-02', 'смуга', (4, 5)) == (3, 3) and П.злам('K-KOH-02', 'смуга', (1, 2)) == (3, 3)
    assert П.ціль_поломки_ошатності(None) is None and П.злам('K-KOH-02', 'смуга', (1, 10)) == (1, 10)
    assert contextvars.Context().run(П.зламані) == frozenset()
