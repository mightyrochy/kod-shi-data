    try:
        with П.прогін(()):
            assert not П.зламані() and П.злам('K-KOH-02', 'смуга', (4, 5)) == (4, 5)
            raise ValueError('навмисний виняток')
    except ValueError:
        pass
    assert П._у('K-CRA-01', П.зламані()) and П.тінь() == тінь
