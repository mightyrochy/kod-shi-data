"""Скарга «Ір» (24.09): «одну й ту саму куртку 3+ разів». Квота K-VAR-01 `частка_речі_набору`: 10 образів,
куртка #7·19 у k з них, її власні джинси «її-ф1» (#1·99) — у всіх 10. Друкує знахідку набору для k = 2, 3, 5.
ДО (main a573f63): куртка в 3 і 5 з 10 — знахідки нема (поріг лише «більше половини»), а її джинси в 10 з 10 — знахідка."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import вердикт_моделі as В
for k in (2, 3, 5):
    об = []
    for i in range(10):
        куртка = "#7·19" if i < k else "#%d·19" % (100 + i)
        н = [куртка, "#1·99", "#%d·06" % (200 + i)]
        об.append(dict(номер="о%d" % (i + 1), речі_н=н, власні_н=["#1·99"],
                       слоти_н={куртка: "верхній_шар", "#1·99": "низ", н[2]: "взуття"}))
    р = (В.різноманітність(об) or {}).get("різноманітність") or {}
    print("ФАКТ · куртка в %d образах із 10, її джинси в 10: ок=%s · %s" % (k, р.get("ок"), р.get("чому")))
# доповнення 207: різні пари, але той самий КЛАС (чоботи) у k образах із 10; пул дав 10 класів
for k in (5, 6, 8):
    об = [dict(номер="о%d" % (i + 1), речі_н=["#%d·06" % (300 + i)], слоти_н={"#%d·06" % (300 + i): "взуття"},
               тип_взуття=("чоботи" if i < k else ("лофери", "човники", "челсі")[i % 3]), класів_взуття_в_пулі=10) for i in range(10)]
    р = (В.різноманітність(об) or {}).get("різноманітність") or {}
    print("ФАКТ · чоботи (різні пари) в %d образах із 10, пул 10 класів: ок=%s · %s" % (k, р.get("ок"), р.get("чому")))
