# -*- coding: utf-8 -*-
"""Звіряє орієнтир кольє, його похибку й відсутні входи без підміни плечем."""
import copy
import pathlib
import sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import accessory as А
import fit as П
import похибка_вимірів_тіла as В

if __name__ == "__main__":
    тіло = П.тіло(168, dict(плечі=98, груди=92, талія=72, стегна=100))
    точка = В.запис("точка_виміру", "основа_шиї")
    пара = [dict(id="кольє", слот="кольє", ланцюг_см=41),
            dict(id="верх", слот="верх", виріз_тип="V-подібний")]
    for назва, висота, похибка in (("нема точки", None, None), ("нема похибки", 144, None),
                                    ("точка з похибкою", точка["середнє"] * 168, точка["val"] * 168)):
        т = copy.deepcopy(тіло)
        if висота is not None:
            т["висоти"]["основа_шиї"] = висота
            т["похибка_висот"]["основа_шиї"] = похибка
        з, = А.кольє_проти_горловини(т, пара)
        assert з["сила"] == "утримано" and з["сила_нп"] == 0
        assert "основа шиї" in з["чому"]
        т["висоти"]["лінія_плеча"] -= 20
        assert А.кольє_проти_горловини(т, пара) == [з], "акроміон впливає на кольє"
        if висота is None:
            assert "нема точки" in з["чому"]
        elif похибка is None:
            assert "похибка невідома" in з["чому"]
        else:
            assert "144.0" in з["чому"] and "0.99" in з["чому"]
        print(назва, "→", з["сила"], з["чому"])
    for т in (None, {}, dict(висоти={})):
        assert len(А.кольє_проти_горловини(т, пара)) == 1
    assert А.кольє_проти_горловини(тіло, пара[:1]) == []
    assert А._край_горловини(dict(виріз_тип="V-подібний"), None)[0] is None
    assert А._край_горловини(dict(край_джерело="річ", верх_см=130), None)[0] == 130
    print("Перевірено: 3 стани точки, незалежність від плеча, відсутнє тіло й вимір речі")
