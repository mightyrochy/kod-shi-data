for ж in ("21", "22"):
    for ф in [ф for ф in git("ls-tree", "-r", "--name-only", "origin/claude/zhyvi-" + ж, ":/аудит/живі_%s/А" % ж).split("\n")
              if ф.endswith("_мовний_шар.txt") and (ж == "22" or "/13_" in ф)]:
        вх, _, ви = git("show", "origin/claude/zhyvi-%s:%s" % (ж, ф)).split("ТЕКСТИ:")[-1].partition("── ВІДПОВІДЬ")
        з_camel += "camel" in вх.lower(); тканин += "camel" in вх.lower() and "кашемір" in ви.lower() and "cashmere" not in вх.lower()
