"""ПЕРЕКЛАД-34 (рядок 4450): що перекладачка тексту картки бачить про кожну річ — ДО (записаний вхід ЖИВІ-21 №13,
ЖИВІ-22 №7, №8: лише англійські тексти) і ПІСЛЯ (той самий вхід + речі картки, `мовний_шар._абзац_речей`). На кожну
річ: чи її українська назва (чи посилання на текст, де назва перекладається) є в промпті. Кращим: ПІСЛЯ — кожна річ.
Запуск: cd джерела && python3 проби/переклад34_речі.py"""
import json, subprocess, sys
sys.path.insert(0, "."); import мовний_шар as МШ
git = lambda *а: subprocess.run(["git", "-c", "core.quotepath=false", *а], capture_output=True, text=True).stdout
for ж, сцена in (("21", "13_ж2_спорт_коментар"), ("22", "07_ж2_новорічна_мороз"), ("22", "08_ж2_спорт_коментар")):
    git("fetch", "-q", "origin", "claude/zhyvi-" + ж)
    звіт = json.loads(git("show", "origin/claude/zhyvi-%s:аудит/живі_%s/А/%s/вердикти.txt" % (ж, ж, сцена)))
    всього = до = після = 0
    for в in [в for п in звіт["прогони"] for в in п["вердикти"]]:
        перший = {}
        for з in [з for з in в.get("мова_шару") or [] if з.get("напрям") == "out" and "language_gate" not in з["де"]]:
            вхід = з.get("вхід") or {}
            речі = [{"н": і + 1, "назва": перший.get("річ.%d.назва" % і) or р["назва"], "ключ": "річ.%d.назва" % і}
                    if "річ.%d.назва" % і in вхід or "річ.%d.назва" % і in перший else {"н": і + 1, "назва": р["назва"]}
                    for і, р in enumerate(в.get("речі_образу") or [])]
            р = МШ.розмітити(вхід)
            пр_до, пр_після = МШ.промпт(р), МШ.промпт(р, речі)
            рядки = []
            for x in речі:
                н = {м["ключ"]: м["н"] for м in р}.get(x.get("ключ"))
                бачить_до = "назва" if x["назва"] in пр_до.split("ТЕКСТИ:")[-1] and not н else "—"
                бачить = ("%d — назва в тексті н=%d" % (x["н"], н)) if н else ("%d — %s" % (x["н"], x["назва"]))
                всього += 1; до += бачить_до != "—"; після += бачить in пр_після
                рядки.append("   річ %d «%s»: ДО %s · ПІСЛЯ %s" % (x["н"], x["назва"][:40], бачить_до,
                                                                  "«%s»" % бачить[:46] if бачить in пр_після else "—"))
            print("Ж%s №%s рука %s · %s · текстів %d" % (ж, сцена[:2], в["рука"], з["де"], len(р)))
            print("\n".join(рядки))
            перший = перший or (з.get("вихід") or {})
    print("Ж%s №%s: речей у викликах %d · українська назва в промпті ДО %d · ПІСЛЯ %d" % (ж, сцена[:2], всього, до, після))
