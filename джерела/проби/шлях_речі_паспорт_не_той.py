"""`спільне.паспорт` і `спільне.чат` у звіті — стан НА МОМЕНТ ВИВАНТАЖЕННЯ, не прогону.

Наслідок: по файлу вердиктів не можна сказати, які речі з фото були закріплені,
коли рука збирала образ. Міряємо часом: час мовного шару прогону проти часу
мовного шару репліки, яку той самий прогін нібито мав на вході."""
import json, os
Ф = os.path.join(os.path.dirname(__file__), "..", "..", "аудит", "тести",
                 "власник_2026-09-25", "verdykty-0phxvk-2026-09-25-2012.json")
d = json.load(open(Ф, encoding="utf-8"))
print("вивантажено: %s" % d.get("вивантажено"))
for п in d["прогони"]:
    с = п["спільне"]
    закр = [р["ід"] for р in ((с.get("паспорт") or {}).get("речі_з_фото") or []) if р.get("закріплена")]
    чатч = [m.get("коли") for r in (с.get("чат") or []) for m in (r.get("мова_шару") or [])]
    фото_у_чаті = [ф["ід"] for r in (с.get("чат") or []) for ф in (r.get("фото") or [])]
    ранні = []
    for в in п["вердикти"]:
        for м in (в.get("мова_шару") or []) + (в.get("мова_шару_примірки") or []):
            if м.get("коли"):
                ранні.append((в["рука"], м["коли"]))
    ранні.sort(key=lambda t: t[1])
    print("\nрозклад %s | паспорт каже закріплено: %s | фото в чаті: %s"
          % (с.get("розклад"), закр or "—", фото_у_чаті or "—"))
    print("  найраніший виклик прогону: %s" % (("рука %s · %s" % ранні[0]) if ранні else "часу нема"))
    print("  мовний шар репліки чату:   %s" % (чатч or "—"))
    if ранні and чатч and ранні[0][1] < min(чатч):
        print("  ⇒ прогін ЗАКІНЧИВСЯ до того, як зʼявилась репліка з цими фото:")
        print("    паспорт і чат у звіті — пізніші за прогін, речі з фото приписані йому заднім числом")
