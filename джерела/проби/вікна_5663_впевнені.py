"""Рядки 6632, 6665 (п.18, рядок 3120): точки поза вікном слова крамниці — вимір, коли впевнений (`вимір_впевнений`).
ФАКТ — скільки записів каталогу мають колір речі точкою, бо `вимір_впевнений` сказав «так», скільки з них темних
(L* < 25), і перелік (id, слот, слово крамниці → код виміру, hex, L*/C*, кадр) — для огляду очима: тінь, тло чи річ.
Запуск: cd джерела && python3 -W ignore проби/вікна_5663_впевнені.py"""
import os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as FK, фід_збагачення as FZ, colorspace as CS
ТАК, _в = set(), FZ.вимір_впевнений
def _свідок(зб, o, кр):
    р = _в(зб, o, кр)
    if р:
        ТАК.add(o["id"])
    return р
FZ.вимір_впевнений = _свідок                      # `колір_спір` кличе ім'я модуля — свідок бачить кожен виклик
К, зб = FK._прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"], FZ.читати_збагачення()
т = [(r, CS.lch(CS.hx(r["колір_hex_фото"]))) for r in К if r["id"] in ТАК and r.get("колір_hex_фото")]
print("ФАКТ · точкою поза вікном (`вимір_впевнений`) %d записів, темних (L* < 25) %d" % (
    len(т), sum(lch[0] < 25 for r, lch in т)))
for r, (L, C, h) in sorted(т, key=lambda x: x[1][0]):
    print("   %-30s %-11s «%s» → %s %s L%.0f C%.1f · %s" % (r["id"], r.get("слот"), r.get("колір_назва_крамниці"),
          r.get("колір_назва_фото"), r["колір_hex_фото"], L, C, (зб.get(r["id"]) or {}).get("фото")))
