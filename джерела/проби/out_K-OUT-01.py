# -*- coding: utf-8 -*-
"""K-OUT-01 (нижче певної температури теплова функція скасовує пропорцію).

ЧОМУ СЛІДУ НЕ БУЛО: правило — не преференція, а ПОРЯДОК ПРАВИЛ, і вмикає його
рівно холод. Батарея аудиту (і стенд, і тест живого шляху) ганяє «офіс, +18 °C»,
де придушення дорівнює нулю, тож голос K-OUT-01 не був потрібен жодного разу.
Емітент і механізм цілі: `придушення_знахідка` говорить ВЛАСНИМ голосом, а не
позначкою на чужих знахідках.
ЩО ПОКАЗУЄ ПРОБА: при −5 °C рядок стоїть у `вердикт.образи[0].знахідки`, і поруч
видно, скільки правил пропорції він придушив."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
вх["сценарій"].update(темп_c=-5, опади="ні")
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
к = з["кандидати"]
# річ береться з КАТАЛОГУ пакета, не лише з пулу: ознака, під яку писане правило,
# трапляється в кожній речі, але лише в холоді, і `перевірити_від_моделі` законно судить річ поза
# кандидатами (вона лише лягає в `поза_кандидатами`) — тим самим шляхом, яким у
# продукт заходить річ, знайдена моделлю в повному каталозі.
ціль = next(c for c in кат.values() if c.get("слот") == "верхній_шар" and (c.get("тип_верхнього") == "пальто" and c.get("довжина_рівень")))
ід = [ціль["id"]] + [(к.get(сл) or [{}])[0].get("id") for сл in ("сукня", "взуття")
                     if (к.get(сл) or [])]
print("верхній шар:", ціль["назва"][:52])
print("ознака входу:", "температура %+.0f°C · придушення %s" % (-5, __import__("outer").придушення(-5)["частка"]))
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
р = next((z for z in (о.get("знахідки") or []) if z.get("правило") == "K-OUT-01"), None)
print("K-OUT-01 у вердикті:", "НЕМА" if not р else
      "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:62]))
print("речі рядка:", (р or {}).get("речі"), "· регістр", (р or {}).get("регістр"))
print("придушено правил:", len([z for z in (о.get("знахідки") or [])
                                  if "придуш" in str(z.get("суть", ""))]) or
      "перелік у суті рядка вище")
