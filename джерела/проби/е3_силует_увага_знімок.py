"""Знімок кожної ваги силуету образу й регістру уваги на каталозі; другий аргумент — коміт ДО."""
import collections, gzip, json, pathlib, sys
КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
sys.path[:0] = [str(КОРІНЬ / 'джерела'), str(КОРІНЬ / 'джерела/проби')]
МОДУЛІ = ('суд_силует', 'регістр_уваги')


def main():
    """Записати сирі й обмежені ваги кожної знахідки (емітент — у полі функції) без моделі."""
    if len(sys.argv) > 2:
        from виконання.е3_база import встановити
        встановити(sys.argv[2], МОДУЛІ)
    import importlib
    from е3_силует_увага_набори import набори
    from реєстр_сила import обмежити_вагу
    м = {ім: importlib.import_module(ім) for ім in МОДУЛІ}
    сирі = {}
    for ім in ('мономісце', 'карта_спідниць'):        # сира вага емітента, до спільної стелі входу
        ориг = getattr(м['суд_силует'], ім)
        def виклик(*a, _о=ориг, _і=ім, **k):
            р = _о(*a, **k)
            сирі.setdefault(_і, []).extend(dict(з) for з in р)
            return р
        setattr(м['суд_силует'], ім, виклик)
    вих, підсумок = [], collections.Counter()
    for назва, модуль, функція, args, kwargs in набори():
        сирі.clear()
        знахідки = getattr(м[модуль], функція)(*args, **kwargs)
        for з in [з for ім in ('мономісце', 'карта_спідниць') for з in сирі.get(ім, [])] or знахідки:
            еф = обмежити_вагу([dict(з)])[0]
            вих.append([назва, функція, з['правило'], з.get('суть'), з.get('речі'), з.get('сила'),
                        з.get('сила_нп'), еф.get('сила_нп'), bool(еф.get('під_підлогою'))])
            підсумок[з['правило'], з.get('сила')] += 1
    with gzip.open(sys.argv[1], 'wt', encoding='utf-8') as ф:
        json.dump(вих, ф, ensure_ascii=False)
    print('знахідок', len(вих), dict(підсумок))


if __name__ == '__main__':
    main()
