# -*- coding: utf-8 -*-
"""CI-1 (рядок 1260): вибір після ремонту повноти ДО вибору — котра спроба в промпті ремонту після вибору.
Показ (показ.html, виклик вибору) шле `повноти_було` = скільки спроб повноти витрачено до вибору; міст читає його
(`міст_відповіді`, `_сп_від`). Друкує ФАКТ: без поля (як було б без показу) і з `повноти_було=1` (як шле показ).
Спроба ≥ 2 несе адресне `бракує` (`повнота_образу.вердикт_повноти`). Запуск із `джерела`: python3 проби/повноти_було_ci1.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge as B
вх = dict(json.load(open("стенд_вх.json")),
          сценарій=dict(нагода="побачення", місце="ресторан", година=19, темп_c=20), випадок="побачення, ресторан, 19:00")
міст = lambda **д: json.loads(B.виклик("від_моделі", json.dumps(dict(вх, **д), ensure_ascii=False)))
пул = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["пакети"]["1"]["пул"]
н = lambda с, i: пул[с][i % len(пул[с])]["н"]
ядро = "сукня" if пул.get("сукня") else "верх"
# п'ять фіналів без сумки: структурна діра, яку вітрина закриває
образи = [dict(ід="о%d" % i, підпис="проба %d" % i, речі=[н(ядро, i), н("взуття", i)]) for i in range(1, 6)]
в2 = міст(ітерація=2, текст_моделі=json.dumps(dict(версія="1", образи=образи), ensure_ascii=False))
print("ітерація 2: образів %d · промпт_повноти_до_вибору: %s · з дірами %s"
      % (len(в2.get("образи") or []), "є" if в2.get("промпт_повноти_до_вибору") else "нема", в2.get("з_дірами_до_вибору")))
# прийнятий склад о1 без сумки (як 966: вибір прийнято, картка неповна) — той самий шлях мосту, що й виклик вибору
склад = [н(ядро, 1), н("взуття", 1)]
for як, дод in (("без повноти_було (ДО)", {}), ("повноти_було=1 (як шле показ)", dict(повноти_було=1))):
    в3 = міст(ітерація=2, ід=склад, попередній_вердикт=в2.get("вердикт"), **дод)
    пр = в3.get("промпт_повноти") or ""
    print("%-32s повний=%s · промпт_повноти: %s · адресне still_missing (спроба ≥ 2): %s"
          % (як, (в3.get("повнота") or {}).get("повний"), "є" if пр else "нема",
             "так" if "still_missing" in пр else "ні"))
