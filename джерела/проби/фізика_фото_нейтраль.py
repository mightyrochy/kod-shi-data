# -*- coding: utf-8 -*-
"""Рядки 1974 і 1975: невідомий колір стає значенням. Каталог руки 1 (пул «запити»).
1974 — кожна річ каталогу як ЇЇ річ із фото, коли фото не дало виміру і слова кольору нема:
скільки дістають рівень «личить» (`item_suits`) і скільки — «невідомо» з `cannot_say_if_suits`.
1975 — нейтраль біля обличчя (верх, сукня, шарф, верхній шар, комплект) на теплій і холодній
особі: скільки категоричних K-COL-06-T, із них за кольором-словом (центр вікна як вимір), і
скільки образів дістають «без входу» (`cannot_tell_neutral_near_face_temperature`). Запуск із `джерела`."""
import sys, json, pathlib, collections
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import feed as Ф, bridge as B, міст_вхід as МВ, річ_з_фото as РФ, композитор_річ as КРІ, outfit as O
import колір_нейтралі as КН, колір_річ as КР, colorspace as cs
вх = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
F, T = МВ._збірка(МВ._нормалізувати_вхід(dict(вх)))[:2]
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml"); вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
рів = collections.Counter()
for c in кат:
    в = РФ.вердикт(dict(слот=c.get("слот"), ід="ф1", фото="x", тип=c.get("тип"), матеріал=c.get("матеріал")), F, T, вх["сценарій"])
    рів[(в["рівень"], "cannot_say_if_suits" in [з["code"] for з in в["повідомлення"]["statements"]])] += 1
print("1974: речей %d як її фото без виміру й слова кольору → %s" % (len(кат), dict(рів)))
ОСОБИ = {"тепла": (cs.features(cs.hx("#deb295"), cs.hx("#f1dbaa"), cs.hx("#759087")), dict(метал="золото", нейтралі="теплі")),
         "холодна": (cs.features(cs.hx("#e8c4b8"), cs.hx("#3a2a25"), cs.hx("#4a6a8a")), dict(метал="срібло", нейтралі="холодні"))}
for ім, (Fо, драп) in ОСОБИ.items():
    n = вирок = словом = пит = 0
    for c in кат:
        if c.get("слот") not in ("верх", "сукня", "шарф", "верхній_шар", "комплект"):
            continue
        E = [e for e in O.елементи([КРІ._у_річ(c, c["слот"], None)]) if e.get("нейтраль")]
        if not E:
            continue
        n += 1
        з = КН.температура_нейтралі(E, Fо, "uncontrolled", драп, "лестити", "conventional", [c])
        т = [x for x in з if x.get("сила") != "питання"]
        вирок += bool(т); словом += bool(т) and КР.не_вимір(E[0]) is not None
        пит += any(x.get("сила") == "питання" for x in з)
    print("1975 (%s особа): нейтралей біля обличчя %d · K-COL-06-T вирок %d, із них за словом %d · без входу %d"
          % (ім, n, вирок, словом, пит))
