# -*- coding: utf-8 -*-
"""Проба переносу реєстру: множина пар «модуль → новий_модуль::ім'я» у теці `поділ_очікувані.d/`
не загубила нічого з json-реєстру до переносу (`поділ_очікувані.json` у БАЗА-коміті). Друкує
лічбу до/після і різницю поіменно. rc 1 — ЩОСЬ ЗНИКЛО; пари, додані після переносу, лише
називаються (це робота гілок, не втрата).
Запуск: cd джерела && python3 проби/поділ_реєстр_перенос.py [БАЗОВИЙ_КОМІТ]"""
import json, os, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from поділ_спільне import очікувані, файли_реєстру
БАЗА = sys.argv[1] if len(sys.argv) > 1 else "de0d834"
було_json = json.loads(subprocess.run(["git", "show", "%s:джерела/проби/поділ_очікувані.json" % БАЗА],
                                      capture_output=True, text=True, check=True).stdout)
було = {(бак, ключ) for бак, пари in було_json.items() if бак != "_опис" for ключ in пари}
баки = sorted(бак for бак in було_json if бак != "_опис")
стало = {(бак, ключ) for бак in баки for ключ in очікувані(бак)}
рядків = sum(1 for ш in файли_реєстру() for р in open(ш, encoding="utf-8")
             if р.strip() and not р.lstrip().startswith("#"))
зникли, додані = sorted(було - стало), sorted(стало - було)
print("реєстр@%s: %d пар у %d модулях · тека: %d записів (рядків: %d, файлів: %d) · "
      "зникло: %d · додано після переносу: %d"
      % (БАЗА, len(було), len(баки), len(стало), рядків, len(файли_реєстру()),
         len(зникли), len(додані)))
for підпис, х in (("зникли:", зникли), ("додані:", додані)):
    if х: print("  ", підпис, х)
sys.exit(1 if зникли else 0)   # додані пари — робота гілок після переносу, не втрата
