# -*- coding: utf-8 -*-
"""Рядок 59 БЕКЛОГ (рішення власника 20.09: «якщо модель і магазини називають його
бежевим, значить він бежевий»): вікно `verify.ЛЕКСИКОН["бежевий"]` до/після,
відкидання виміру з фото (`verify.перевірити` на `каталог_збагачення.json.gz`,
слово моделі проти її hex) до/після і клітинки `міст_основи.ґратка_основ`, що
змінили ім'я. Запуск із теки `джерела`: `python3 проби/leks_bezhevyi_59.py`.

Ім'я «бежевий» клітинки, що лежить у вікні вжитку «бежевий», — наслідок слова власника (п.9 журналу),
а не перейменування: проба стереже лише зміни імен ґратки поза вжитком слова (рішення менеджера 08.11,
14005; крок 26 — клітинка #eed1cd у вікнах вжитку «молочний» і «бежевий»)."""
import sys, pathlib, json, gzip, re
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import verify as V, colorspace as cs, міст_основи as M

БУЛО = (60, 90, 6, 30, (45, 105))          # вікно до 20.09.2026 (T3, #114/#122)
# ВАЖІЛЬ — ВІКНО ВЖИТКУ, А НЕ ПІДПИСУ (27.09.2026, рядок 173). Доти проба рухала
# `V.ЛЕКСИКОН["бежевий"]`, і після хвилі Л-10 цей важіль перестав рухати те, що вона
# міряє: `verify.перевірити` судить вимір вікном ВЖИТКУ (`вікно_вжитку`), а ЛЕКСИКОН
# лишився підписом точки (`palettes.назва`). Через те дослід був інертний — «відкидань
# «бежевий» 2 → 2» на будь-якому вікні, — і проба червоніла на власній умові «спад є»,
# не показуючи жодної поломки продукту. Тепер `ТЕПЕР` — чинне ДІЙОВЕ вікно, а `лічба`
# рухає обидві таблиці в лад: вжиток судить вимір, лексикон називає клітинку ґратки.
ТЕПЕР = V.вікно_вжитку("бежевий")
import колір_річ as _КОЛІР
with gzip.open("каталог_збагачення.json.gz", "rt", encoding="utf-8") as f:
    РЕЧІ = [(к["слово"], cs.hx(_КОЛІР.hex_кольору(к))) for зб in json.load(f).values()
            if (к := (зб or {}).get("колір_основний") or {}).get("слово") in V.ЛЕКСИКОН
            and re.fullmatch(r"#?[0-9a-fA-F]{6}", str(_КОЛІР.hex_кольору(к) or ""))]

def лічба(вікно):
    V.ЛЕКСИКОН["бежевий"] = вікно; V.ВЖИТОК["бежевий"] = вікно
    M.ҐРАТКА_КЕШ.clear(); осн, поряд = M.ґратка_основ()
    відк = [с for с, lab in РЕЧІ if V.перевірити(lab, назва=с)["вердикт"] == "відкинуто"]
    return len(відк), відк.count("бежевий"), {k: осн[k] for k in поряд}

def у_вжитку(слово, hx):
    """Чи точка лежить у чинному вікні вжитку слова (L*, C*, дуга тону)."""
    в = V.вікно_вжитку(слово)
    L, C, h = cs.lch(cs.hx(hx))
    return bool(в) and в[0] <= L <= в[1] and в[2] <= C <= в[3] and (в[4] is None or V.у_дузі(h, в[4]))

в_до, б_до, ґ_до = лічба(БУЛО)
в_після, б_після, ґ_після = лічба(ТЕПЕР)
print("вікно «бежевий»: %s → %s" % (БУЛО, ТЕПЕР))
print("речей зі словом лексикону й hex: %d" % len(РЕЧІ))
print("відкидань усіх: %d → %d · «бежевий» проти виміру: %d → %d" % (в_до, в_після, б_до, б_після))
ім = lambda ґ, k: (ґ.get(k) or (None, None))[1]
зм = [(k, ім(ґ_до, k), ім(ґ_після, k)) for k in sorted(set(ґ_до) | set(ґ_після)) if ім(ґ_до, k) != ім(ґ_після, k)]
вжиток = [з for з in зм if з[2] == "бежевий" and у_вжитку("бежевий", ґ_після[з[0]][0])]
зм = [з for з in зм if з not in вжиток]
print("клітинок ґратки: %d → %d · «бежевий» за вжитком: %d %s" % (len(ґ_до), len(ґ_після), len(вжиток),
      [(k, ґ_після[k][0], [с for с in ("молочний", "бежевий") if у_вжитку(с, ґ_після[k][0])]) for k, _, _ in вжиток]))
print("змінили ім'я поза вжитком: %d %s" % (len(зм), зм or ""))
білі = [k for k, (_, ім_) in ґ_після.items() if "нейтраль" in k and ім_ == "білий"]
print("світлі ахроматичні клітинки досі «білий»: %d %s" % (len(білі), білі))
ок = б_після < б_до and not зм and ТЕПЕР[1] > БУЛО[1] and білі
print("ОК" if ок else "ЗЛАМАНО"); sys.exit(0 if ок else 1)
