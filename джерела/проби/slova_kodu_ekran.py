# -*- coding: utf-8 -*-
"""Ш-1 (аудит/ПРОДУКТ.md пп.7, 12): скільки текстів ДЛЯ ЖІНКИ називають «код» дійовою особою — літерали
й текст HTML у `показ.html` (ланцюг склеювання — цілком) плюс визначення повідомлень у
`внутрішня_мова.py` (хвіст «(значення: …)» — дані, не фраза). Звіту й діагнозу власника та
блоку «код не знає» (п.9) не лічить. Прогін: python3 проби/slova_kodu_ekran.py [git-рев]."""
import io, os, re, subprocess, sys
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
СЛОВО = re.compile(r"\bкод(?:у|ом|і|ові|а)?\b", re.I)
НЕ_ЖІНЦІ = re.compile(r"ЗБ\.діагноз|як_читати|new Error|запамʼятатиЗапит|питання-коду|повідомленнямП\("
                      r"|неповнийЧому =|полів_збірка_не_писала|\{крок:|код не знає ·")
ЛІТЕРАЛ = re.compile(r"'([^'\\\n]*(?:\\.[^'\\\n]*)*)'|\"([^\"\\\n]*(?:\\.[^\"\\\n]*)*)\"|>([^<>]+)<")
БЛОК_П9 = "«КОД НЕ ЗНАЄ» НА КАРТЦІ"          # службова назва, яку дав власник, — не чіпаємо

def показ(текст):
    ряд = re.sub(r"<!--.*?-->|/\*.*?\*/", lambda м: re.sub(r"[^\n]", " ", м.group(0)),
                 текст, flags=re.S).split("\n"); знах = []
    for i, р in enumerate(ряд):
        for м in ЛІТЕРАЛ.finditer(р):
            if not СЛОВО.search(м.group(1) or м.group(2) or м.group(3) or ""):
                continue
            j, ланцюг = i, р              # ланцюг склеювання назад, поки рядок тягне далі
            while j > 0 and (ряд[j].lstrip()[:1] in "+?:" or ряд[j - 1].rstrip()[-1:] in "+(,?:"):
                j -= 1; ланцюг = ряд[j] + " " + ланцюг
            if not НЕ_ЖІНЦІ.search(ланцюг):
                знах.append(("показ.html:%d" % (i + 1), " ".join(м.group(0).split())[:108]))
    return знах

def мова(текст):
    п = {"__file__": "внутрішня_мова.py"}; exec(compile(текст, "внутрішня_мова.py", "exec"), п)
    хвіст = текст.split(БЛОК_П9)[1] if БЛОК_П9 in текст else ""
    свої = set(re.findall(r'"([a-z_0-9]+)":', хвіст)) | {"card_unchecked"}
    return [("внутрішня_мова:%s" % к, " ".join(з.split("(значення:")[0].split())[:108])
            for д in ("ВИДИ_ПОВІДОМЛЕНЬ", "ЗАЯВИ") for к, з in (п.get(д) or {}).items()
            if к not in свої and СЛОВО.search(str(з).split("(значення:")[0])]
злічити = lambda бр: показ(бр("показ.html")) + мова(бр("внутрішня_мова.py"))
стало, рев = злічити(lambda ф: io.open(ф, encoding="utf-8").read()), (sys.argv[1:] or ["origin/main"])[0]
try: було = len(злічити(lambda ф: subprocess.check_output(["git", "show", "%s:джерела/%s" % (рев, ф)]).decode()))
except Exception as e: було = "не зчитано (%s)" % e
print("«код» дійовою особою в текстах для жінки: було (%s) %s · стало %d" % (рев, було, len(стало)))
print("\n".join("  %-34s %s" % р for р in стало) or "  порожньо")
