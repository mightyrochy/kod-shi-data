"""Р2-2г (рядок 432): K-REG-01 після #503 — чи пара для живої моделі не порожня. Для сідів, де жереб бере K-REG-01
(з 15.10 — серед кількох правил, рядок 5503), друкує пару, рядки брифа рук 1 і 2 (`правила_рук` B/C) і чи пакети рук без
пулу однакові (порядок речей руки 2 свій — рядок 5505); рядок, якого нема в руки 2, — з кодом.
Запуск: cd джерела && python3 проби/рука2_регістр.py"""
import os, sys, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge as B
вх0 = json.load(open("стенд_вх.json")); сц = dict(нагода="робота", місце="офіс", година=9, темп_c=18, дрес_код="business_casual")
n = різн = 0
for сід in range(1, 60):
    з = json.loads(B.виклик("запити", json.dumps(dict(вх0, каталог="каталог_повний.xml", сід=сід, сценарій=сц), ensure_ascii=False)))
    п = з["поломка"]
    if "K-REG-01" not in п.get("правила", [п["правило"]]): continue
    р1, р2 = [{x.get("код") for x in з["правила_рук"][к]} for к in "BC"]
    пк1, пк2 = [{к: в for к, в in з["пакети"][р].items() if к != "пул"} for р in "12"]
    n += 1; різн += (р1 != р2) or (пк1 != пк2)
    print("сід %d · %s · %s · брифа руки 1 %d рядків, руки 2 %d · лише в руки 1: %s · пакети рук без пулу однакові: %s" % (
        сід, п["правило"], п["що_змінено"].split("pair=")[1].split(" ")[0], len(р1), len(р2), sorted(р1 - р2), пк1 == пк2))
print("сідів з K-REG-01: %d · пара не порожня (бриф чи пакет різняться): %d" % (n, різн))
