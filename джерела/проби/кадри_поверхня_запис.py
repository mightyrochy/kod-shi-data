"""Записувач галереї зберігає справжню поверхню й не пише точку непридатної маски чи розкиду поза одним вікном коду."""
import os, sys, tempfile
from unittest.mock import patch
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import жнива_кадри as Ж, жнива_колір as П, фід_кадр_колір as К
from жнива_фото import читати_bgr


def головна():
    """Прогнати збережені RGB і маску через поверхню та справжній цикл запису кадру."""
    тека = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
                        "аудит", "проби", "поверхня_212")
    bgr = читати_bgr(os.path.join(тека, "00.jpg"))
    маска = читати_bgr(os.path.join(тека, "00.маска.png"))[:, :, 0]
    арр = читати_bgr(os.path.join(тека, "00.atr.png"))[:, :, 0]
    поверхні = [П.виміряти_поверхню(bgr, маска, арр, джерело="ATR"),
                П.виміряти_поверхню(bgr, маска, арр, джерело="запасна")]
    assert [п["придатна"] for п in поверхні] == [True, False]
    with tempfile.TemporaryDirectory() as тимч:
        for джерело, п in zip(("ATR", "запасна"), поверхні):
            вимір = dict(поверхня=п, частка=0.32, джерело="ATR", чому=п["чому"],
                         кластери=п["сегменти"] if п["придатна"] else [])
            with patch.multiple(Ж, КЕШ=тимч, тип_речі=lambda o: ("штани", "низ"),
                                _адреси_речі=lambda *a: (["https://x/a.jpg"], "k"),
                                взяти_кадр=lambda *a: dict(шлях="fixture.jpg"),
                                поверхня_фото=lambda *a: вимір):
                запис = Ж.виміряти_річ({}, {}, {}, {}, 1, False, 1, None, кеш=True)[0]
            assert запис["вимір"] == П.стиснути_поверхню(п)
            # код з виміру — придатна поверхня й головний сегмент без `колір_не_вимір`: розкид (поправка тла
            # ×1,00…k, C ± U) в одному вікні коду (рішення менеджера 08.11, п.1); інакше — «невідомо» з межами
            вимір_є = п["придатна"] and "колір_не_вимір" not in п["сегменти"][0]
            assert bool(К.вимір_кадру(запис)) == вимір_є
            assert ("lab" in запис) == вимір_є
            if вимір_є:
                assert запис["розкид"] == п["сегменти"][0]["розкид"]
            elif п["придатна"]:
                assert запис["колір_тип"] == "невідомо" and запис["колір_не_вимір"]["свідок"] == "partial_measure"
            print("маска %s: тип %s; придатна %s; розкид %s" %
                  (джерело, запис["колір_тип"], запис["придатна"], запис.get("розкид")))


if __name__ == "__main__":
    головна()
