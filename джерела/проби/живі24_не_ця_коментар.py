"""НЕ-ЦЯ-36 (рядок 4680): «не ця» з коментаря — лише на `dislike` з причиною. Записи перекладача коментаря ЖИВІ-12…24
(гілки `claude/zhyvi-N`, дублі за змістом — раз) тим кодом, що в теці аргументу (типово `.`), швом показу:
`прийняти_вхід("verdict_comment", ід речей картки)` → `паспорт_з_коментаря`. Друкує на кожен коментар: записів, скільки дали
`не_ця`, скільки `dislike` знято як `dislike_without_reasons`, скільки лягли межі. Кращим: «Колір мій, а жакет…» (про
взуття ні слова) — `не_ця` лише там, де модель дала причину; «взуття не моє, без каблука…» — `не_ця` і межі в кожному.
Запуск: cd джерела && python3 проби/живі24_не_ця_коментар.py [тека джерел іншої збірки]"""
import json, re, subprocess, sys
sys.path.insert(0, sys.argv[1] if len(sys.argv) > 1 else "."); import мовний_шар as МШ
git = lambda *а: subprocess.run(["git", "-c", "core.quotepath=false", *а], capture_output=True, text=True).stdout
бачено, лічба = set(), {}
for ж in range(12, 25):
    гілка = "origin/claude/zhyvi-%d" % ж
    git("fetch", "-q", "origin", "claude/zhyvi-%d" % ж)
    for шлях in git("grep", "-l", "перекладаєш коментар жінки до образу", гілка, "--", ":(top)аудит").split():
        т = git("show", шлях)
        м = re.search(r"\nСЛОВА:\n(.*?)\n\nКОНТЕКСТ:\n(.*?)\n\n── ВІДПОВІДЬ[^\n]*\n(.*)", т, re.S)
        if not м or т in бачено:
            continue
        бачено.add(т)
        речі = json.loads(м.group(2)).get("items") or []
        р = МШ.прийняти_вхід("verdict_comment", м.group(3), ід_речей={x["id"] for x in речі},
                             слоти_речей={x["id"]: x.get("slot") for x in речі}, слова=м.group(1))
        к = МШ.паспорт_з_коментаря(р["внутрішня"], {"перекладено_шаром": True, "вето": {}})
        л = лічба.setdefault(м.group(1)[:40], [0, 0, 0, 0])
        л[0] += 1
        л[1] += bool(к["не_ця"])
        л[2] += any("dislike_without_reasons" in x for x in р["незнайомі"])
        л[3] += bool(к["додано"]["вето"])
for слова, (усього, не_ця, знято, межі) in sorted(лічба.items(), key=lambda x: -x[1][0]):
    print("%-42s записів %2d · не_ця %2d · dislike без причини знято %2d · межі %2d" % (слова, усього, не_ця, знято, межі))
