"""Рядок 3655: перелік рук 3–4 — речей на картці ДО (слот лише дослівним кодом) → ПІСЛЯ (`_речі_структурою`).
Вхід: файли VIDPOVIDI `…перелік_речей_руки_3_4_.txt` (аргументи); розбір — як у показі. Друкує зміну лише там, де вона є.
Запуск: cd джерела && python3 проби/слоти_перелік_replay.py <файл>…"""
import os, sys, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import руки_без_коду as РБК, розбір_відповідей as РВ, внутрішня_мова as ВМ
всього = [0, 0]
for шлях in sys.argv[1:]:
    т = open(шлях, encoding="utf-8").read()
    відп = т.split("── ВІДПОВІДЬ", 1)[1].split("\n", 1)[1] if "── ВІДПОВІДЬ" in т else ""
    структ = РБК.речі_переліку(відп)
    if not структ:
        continue
    до = sum(1 for р in структ if р["носить"] and ВМ.ключ("slot", р["код_слота"]))
    р = РВ._речі_структурою(структ)
    після = len(р["речі"])
    всього[0] += до; всього[1] += після
    if до != після or р["без_слота"]:
        print(os.path.basename(шлях)[:40],
              "названо=%d ДО=%d ПІСЛЯ=%d" % (len(структ), до, після), "без_слота=%s" % [б["код"] for б in р["без_слота"]])
print("файлів %d · речей на картках ДО=%d ПІСЛЯ=%d" % (len(sys.argv) - 1, *всього))
