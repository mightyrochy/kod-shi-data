"""Рядок 731: колготи класу площі не мають — образ із колготами лишався без площ (гейт K-COL-01/06).
Друкує частоту колгот у каталозі руки 1 і `outfit.площі_з_геометрії` на трьох образах з колготами:
міні-спідниця, спідниця міді з ботильйонами (край взуття виміряний), штани в підлогу.
Моделі не кличе. Запуск: cd джерела && python3 проби/колготи_площа_731.py"""
import collections, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import fit as ПС, outfit as O, feed, фід_каталог as ФК                       # noqa: E401,E402
кат = ФК._прочитати_каталог(feed.каталог_на_диску(), ліміт_фото=0)["каталог"]
сл = collections.Counter(r.get("слот") for r in кат)
print("каталог руки 1: %d речей · колготи %d · шкарпетки %d" % (len(кат), сл.get("колготи", 0), сл.get("шкарпетки", 0)))
T = ПС.тіло(168, dict(плечі=98, груди=92, талія=74, стегна=99, високе_стегно=88))
верх = dict(id="светр", слот="верх", hex="#8a7f74", верх_см=140, низ_см=95)
колготи = dict(id="колготи", слот="колготи", hex="#1c1b1d")
for назва, низ, взуття in (
        ("міні + туфлі (край взуття — дефолт)", dict(id="спідниця", слот="низ", hex="#5b4e4d", верх_см=100, низ_см=72),
         dict(id="туфлі", слот="взуття", hex="#22201e")),
        ("міді + ботильйони (край виміряний)", dict(id="спідниця", слот="низ", hex="#5b4e4d", верх_см=100, низ_см=40),
         dict(id="ботильйони", слот="взуття", hex="#22201e", верх_см=22, низ_см=0, край_джерело="виріб")),
        ("штани в підлогу", dict(id="штани", слот="низ", hex="#5b4e4d", верх_см=100, низ_см=3),
         dict(id="туфлі", слот="взуття", hex="#22201e"))):
    речі, звіт = O.площі_з_геометрії([dict(верх), низ, взуття, dict(колготи)], T)
    к = next(r for r in речі if r["id"] == "колготи")
    print("%-38s покриття %s · колготи: площа %s (%s, %s)\n    чому: %s" % (
        назва, звіт["покриття"], к.get("площа"), к.get("джерело_площі"), к.get("площа_проміжок"), звіт["чому"][:150]))
