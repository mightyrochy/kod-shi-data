sys.path.insert(0, ".")
import json, протокол as П
Г = "origin/claude/zhyvi-13"
git = lambda *а: subprocess.run(["git", "-c", "core.quotepath=false", *а], capture_output=True, text=True).stdout
файли = [ф for ф in git("ls-tree", "-r", "--name-only", Г, "--", "../аудит/живі_13/").split("\n")
         if re.search(r"/VIDPOVIDI/.*(ОБРАЗИ_V1|повтор_формату)", ф)]
разом = нуль = 0
for ф in файли:
    т = git("show", "%s:%s" % (Г, ф))
    в = т.partition("── ВІДПОВІДЬ")[2].partition("\n")[2].strip()
    об, причина, нот = П.розбір_за_схемою(в, "ОБРАЗИ_V1")
