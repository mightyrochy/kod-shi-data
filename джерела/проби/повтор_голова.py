# -*- coding: utf-8 -*-
"""В-1: яка річ стоїть ЗГОРИ слота в промпті складання — на п'яти сідах × дві руки.

Модель бере згори (Д-1, `повтор_позиція.py`: перша річ слота — 12 % виборів проти 3 %),
тож «та сама річ першою» = «та сама річ в образах». Проба читає пул обʼєктом пакета
(`запити` → `пакети`, П-2) — тим самим порядком, яким він стоїть у промпті складання (англійський
дріт кладе слоти пулу один за одним, `дріт_моделі.пул`), номер «н» переводить в id тією самою нумерацією
(`пакет_моделі.номери_речей`) і друкує по слотах: скільки РІЗНИХ речей стояло першими
і скільки — серед перших трьох за 10 промптів (5 сідів × руки 1 і 2).
Прогін: python3 проби/повтор_голова.py     (~1.5 хв: п'ять збирань)
"""
import collections, json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed as Ф, bridge as B, міст_пакет as МП, пакет_моделі as PM
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), каталог=Ф.каталог_на_диску("каталог_повний.xml"))
перші, трійки, довжини = collections.defaultdict(list), collections.defaultdict(list), collections.defaultdict(list)
for сід in (1, 7, 42, 4242, 31337):
    МП._КЕШ_ПАКЕТА.clear()
    r = json.loads(B.виклик("запити", json.dumps(dict(вх, сід=сід), ensure_ascii=False)))
    за_н = {}
    for пк in [p for p in МП._КЕШ_ПАКЕТА.values() if p.get("кандидати")]:
        ном, _ = PM.номери_речей(пк["кандидати"])
        за_н[пк["текст"]] = {"#%d·%s" % v: k for k, v in ном.items()}
    for рука in ("1", "2"):
        текст = r["руки"][рука]
        пул, мапа = r["пакети"][рука]["пул"], за_н.get(текст, {})
        for с, рч in пул.items():
            ід = [мапа.get(x["н"], x["н"]) for x in рч]
            перші[с].append(ід[0]); трійки[с].extend(ід[:3]); довжини[с].append(len(ід))
print("%-14s %6s %13s %15s" % ("слот", "довж.", "різних 1-х", "різних у 1–3"))
for с in sorted(перші, key=lambda к: -max(довжини[к])):
    print("%-14s %6d %8d з %2d %10d з %2d" % (с, max(довжини[с]), len(set(перші[с])), len(перші[с]),
          len(set(трійки[с])), len(трійки[с])))
print("РАЗОМ різних речей ПЕРШИМИ: %d із %d промпто-слотів; у перших трьох — %d із %d"
      % (sum(len(set(v)) for v in перші.values()), sum(len(v) for v in перші.values()),
         sum(len(set(v)) for v in трійки.values()), sum(len(v) for v in трійки.values())))
