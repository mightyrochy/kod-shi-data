"""Рядок 3770: записані переліки рук 3–4 → речі КАРТКИ (`перевірити_образ_моделі`, як міст) і `slot_unknown`.
Вхід: файли VIDPOVIDI `…перелік_речей_руки_3_4_.txt` (аргументи); опис руки — з промпту переліку («description»).
Друкує файли, де є річ без слота або річ нового слота, і підсумок. Запуск: cd джерела && python3 проби/слоти_повні_replay.py <файл>…"""
import os, sys, json, warnings
warnings.simplefilter("ignore")
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import розбір_відповідей as РВ, внутрішня_мова as ВМ
СТАРІ = {"верх", "низ", "сукня", "комплект", "верхній_шар", "взуття", "сумка", "шарф", "головний_убір", "пояс",
         "колготи", "шкарпетки", "прикраси", "сережки", "кольє", "намисто", "брошка", "браслет", "каблучка", "окуляри"}
файлів, на_картці, невідомих = 0, 0, 0
for шлях in sys.argv[1:]:
    т = open(шлях, encoding="utf-8").read()
    if "── ВІДПОВІДЬ" not in т:
        continue
    запит, відп = т.split("── ВІДПОВІДЬ", 1)
    відп = відп.split("\n", 1)[1]
    try:
        опис = json.loads(запит.split("\n", 1)[1].strip())["input"]["description"]
    except (ValueError, KeyError, TypeError):
        опис = ""
    в = РВ.перевірити_образ_моделі(опис, None, перелік=відп)
    р = в["розбір"]
    файлів += 1; на_картці += len(в.get("речі") or []); невідомих += len(р.get("без_слота") or [])
    нові = [(x["слот"], x["назва"][:30]) for x in в.get("речі") or [] if x["слот"] not in СТАРІ]
    if р.get("без_слота") or нові:
        print(os.path.basename(шлях)[:44], "на_картці=%d" % len(в.get("речі") or []),
              "slot_unknown=%d %s" % (len(р["без_слота"]), [б["код"] for б in р["без_слота"]]), "нові=%s" % нові)
print("слотів у таблиці %d · файлів %d · речей на картках %d · slot_unknown %d"
      % (len(ВМ.ТАБЛИЦЯ["slot"]), файлів, на_картці, невідомих))
