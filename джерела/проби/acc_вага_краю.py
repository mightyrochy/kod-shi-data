"""Вага халяви й подолу на точному геометричному вході; це синтетична проба."""
import json
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))


def main():
    """Досягти обох ID спільної емісії без невідомої похибки ширини литки."""
    import fit
    import accessory
    вх = json.loads((Path(__file__).resolve().parents[1] / 'стенд_вх.json').read_text(encoding='utf-8'))
    т = fit.тіло(float(вх['зріст']), {к: float(з) for к, з in dict(вх['обхвати'], литка=55).items()})
    # Точність нуль — означення ідеалізованої фікстури, не оцінка самовиміру жінки.
    т.update({к: dict.fromkeys(т[к], 0.0) for к in ('похибка_ширин', 'похибка_висот')})
    y = т['висоти']['литка']
    for зсув in (-1, 0, 1):
        речі = [dict(id='халява', назва='халява', слот='взуття', халява_см=y + зсув),
                dict(id='поділ', назва='поділ', слот='сукня', верх_см=y + 50,
                     низ_см=y + зсув, край_джерело='річ')]
        зн = accessory.халява_і_поділ(т, речі)
        assert {з['правило'] for з in зн} == {'K-SHO-05', 'K-SHO-11'}, зн
        print(зсув, [(з['правило'], з['сила'], з['сила_нп']) for з in зн])


if __name__ == '__main__':
    main()
