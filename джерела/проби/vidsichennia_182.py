"""Рядок 182, доробка: читачі, що ВИРІШУЮТЬ за назвою, читають назву картки, а не речення фіду.
ДО — `_жорстке_відсічення` і `шукати_словами` над СИРОЮ назвою, ПІСЛЯ — над відновленою.
Запуск: cd джерела && python3 проби/vidsichennia_182.py"""
import collections, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as ФК, пакет_моделі as ПМ
кат = ФК._прочитати_каталог(feed.каталог_на_диску(), ліміт_фото=0)["каталог"]
з_назвою = [r for r in кат if r.get("назва_показу")]
ПОРОГИ = ((30.0, None), (26.0, None), (16.0, None), (None, 7), (None, 6))
змін, приклади = collections.Counter(), {}
for r in з_назвою:
    сира = dict(r); сира.pop("назва_показу", None); сира.pop("назва_показу_джерело", None)
    for темп, ошат in ПОРОГИ:
        а = ПМ._жорстке_відсічення(сира, темп_c=темп, ошатність=ошат)
        б = ПМ._жорстке_відсічення(r, темп_c=темп, ошатність=ошат)
        if а == б: continue
        к = "темп %s°C" % темп if темп is not None else "ошатність %d" % ошат
        змін["%s · %s" % (к, "відсічено тепер" if б else "перестало відсікатись")] += 1
        приклади.setdefault(к + str(bool(б)), (r["id"], r["назва_показу"][:36], а, б))
print("ФАКТ · у записі каталогу відновлену назву несуть %d речей із %d" % (len(з_назвою), len(кат)))
print("ФАКТ · рішень `_жорстке_відсічення`, що змінились: %d" % sum(змін.values()))
for к, n in sorted(змін.items()):
    print("ФАКТ ·   %-44s %d" % (к, n))
for _, (ід, н, а, б) in sorted(приклади.items()):
    print("ФАКТ · %s «%s» · ДО %s → ПІСЛЯ %s" % (ід, н, а or "лишалась", б or "лишається"))
for фраза in ("практичний", "теплий", "зимовий пуховик"):
    а = {r["id"] for r in ПМ.шукати_словами([dict(r, назва_показу=None) for r in кат], фраза, n=8, темп_c=16.0)}
    б = {r["id"] for r in ПМ.шукати_словами(кат, фраза, n=8, темп_c=16.0)}
    print("ФАКТ · «%s» (+16°C): ДО %s" % (фраза, sorted(а)))
    print("ФАКТ · %s  ПІСЛЯ %s" % (" " * (len(фраза) + 10), sorted(б)))
