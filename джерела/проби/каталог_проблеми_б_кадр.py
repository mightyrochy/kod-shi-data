"""Реєстр проблем каталогу, напрям Б, клас Б2: колір виміряно на кадрі іншого варіанта або не на тому кадрі, що бачить жінка.
Рядки 142, 3351, 5027 (фід не несе зв'язку кадр→варіант: 0/1384). ФАКТ — заяви `кадр_кольору` («інший_колір» — кадр
картки показує інший колір, ніж слово речі) і доказ, яким код зв'язав кадр із варіантом (ім'я файла, артикул, назва —
явного зв'язку з фіду нема). Вибір і чистота кадрів — напрям А; тут лише наслідок для кольору.
Запуск: cd джерела && python3 -W ignore проби/каталог_проблеми_б_кадр.py"""
import collections, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as FK
К = FK._прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"]
ст = collections.Counter((r.get("кадр_кольору") or {}).get("стан") for r in К if r.get("кадр_кольору"))
крам = collections.Counter(r["магазин"] for r in К if (r.get("кадр_кольору") or {}).get("стан") == "інший_колір")
пари = collections.Counter(((r["кадр_кольору"].get("слово"), r["кадр_кольору"].get("фото")))
                           for r in К if (r.get("кадр_кольору") or {}).get("стан") == "інший_колір")
print("ФАКТ · записів %d; заява кадру кольору: %s; «інший_колір» по крамницях %s" % (len(К), dict(ст), крам.most_common(6)))
print("ФАКТ · найчастіші пари «слово речі → колір кадру картки»: %s" % пари.most_common(6))
ім = collections.Counter((r.get("колір_варіант") or {}).get("джерело") for r in К if r.get("колір_варіант"))
файл = sum("ім'я файла" in (r.get("колір_варіант") or {}).get("за_чим", "") for r in К)
print("ФАКТ · кадр↔варіант зв'язано здогадкою (не полем фіду): %s; з них за ім'ям файла кадру %d" % (dict(ім), файл))
