# -*- coding: utf-8 -*-
"""ГГ-ОГЛЯД (09.10, рядки 2660, 2664): чи дістають образи на `каталог_повний` ОПОРИ ГГ-1 у живому суді
(`pipeline.перевірити_від_моделі`, без моделі). (а) 4 сцени × мета {типова, «вище»} × 10 випадкових образів із
кандидатів пулу (з сумкою, шарфом, сережками, намистом), сід 7: скільки з опорою і яких правил. (б) чому відлуння
K-ACC-01 майже не стає опорою: гучні (C*≥40, `аксесуари_структура._C_речі`) кандидати — тон виміряний (точка) чи
вікно слова; пари «гучний одяг × гучний аксесуар» за `колір_річ.поруч_за_тоном(…, ДУГА_ВІДЛУННЯ)`: опора — лише «так».
(в) те саме на всьому каталозі: гучних речей точкою / вікном. Запуск із джерела/: python3 проби/гг_опори_каталог.py"""
import json, os, random, sys, collections as K
Д = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, Д); os.chdir(Д)
import bridge as B, fit as ПС, colorspace as cs, pipeline as PL, стенд_знімок as СЗ, колір_річ as КР, аксесуари_структура as АС
from суд_ремесло import ДУГА_ВІДЛУННЯ
вх0 = json.load(open("стенд_вх.json", encoding="utf-8"))
T = ПС.тіло(float(вх0["зріст"]), {k: float(v) for k, v in вх0["обхвати"].items()})
F = cs.features(cs.hx(вх0["шкіра"]), cs.hx(вх0["волосся"][0]), cs.hx(вх0["очі"]))
СЛОТИ = ("верх", "низ", "сукня", "верхній_шар", "взуття", "сумка", "шарф", "сережки", "намисто")
Л, П = K.Counter(), K.Counter()
гучна = lambda x: (АС._C_речі(x) or 0.0) >= 40
вид = lambda x: "точка" if КР.не_вимір(x) is None else "вікно слова"
for назва in ("офіс·18°C", "дощ·ресторан·вечір", "весілля·гість", "спека·парк"):
    for мета in (None, "вище"):
        сц = dict(СЗ.СЦЕНАРІЇ[назва], **({"мета": мета} if мета else {}))
        к = json.loads(B.виклик("запити", json.dumps(dict(вх0, сценарій=сц, випадок=назва), ensure_ascii=False)))["кандидати"]
        кат, rnd = B.каталог_останнього_пакета(), random.Random(7); зі = {r["id"]: r for r in кат}
        for n in range(10):
            ід = [rnd.choice(к[с])["id"] for с in СЛОТИ if к.get(с) and с not in (("верх", "низ") if n % 2 == 0 else ("сукня",))]
            оп = PL.перевірити_від_моделі(ід, F, кат, T, сценарій=dict(сц), кандидати=к).get("опори") or []
            Л["(а) з 40 образів%s: з опорою" % (" · мета вище" if мета else "")] += bool(оп); П.update(o["правило"] for o in оп)
        if мета: continue
        г = [(с, dict(зі[r["id"]], слот=с)) for с, рр in к.items() for r in рр if гучна(зі.get(r["id"]) or {})]
        for с, x in г: Л["(б) гучних кандидатів, %s: %s" % ("аксесуар" if с in АС.СЛОТИ_АКСЕСУАРІВ else "одяг", вид(x))] += 1
        for с1, x in г:
            for с2, y in г:
                if с1 not in АС.СЛОТИ_АКСЕСУАРІВ and с2 in АС.СЛОТИ_АКСЕСУАРІВ:
                    Л["(б) пар гучний одяг × гучний аксесуар: " + КР.поруч_за_тоном(y, x, ДУГА_ВІДЛУННЯ)] += 1
for x in кат: Л["(в) каталог, гучних речей: " + вид(x)] += гучна(x)
for к, v in sorted(Л.items()): print("  %-58s %s" % (к, v))
print("  (а) опори за правилом:", dict(П))
