# -*- coding: utf-8 -*-
"""Інваріанти сімей кольору `колір_тон`: сили, вердикт (сім'я чи пара), ворота тону й відносна температура.

Читачів сімей на модуль ще не переключено (паспорт `аудит/корені/Річ-колір-межі.md`, п.2), тож живий шлях цих
функцій не виконує; мірило кроку на каталозі — `аудит/перевірка/річ_колір_межі_сім_ї_20261105/мірило_сімей.py`.
Ця проба — дешева звірка рішень модуля на сітці sRGB, осі нейтралей і променях хроми:
  · сили — невід'ємні, сума 1, за спаданням;
  · вердикт — найсильніша сім'я, друга лише з силою ≥ `значна_сила` (Φ(−1)); «невідомо» — лише коли сила без даних
    більша за силу кожної сім'ї; `сім_я_кольору` — перша сім'я `сім_ї_кольору`;
  · вісь L* 0–100 при a = b = 0 — одна сім'я achromatic (рішення 05.11 щодо білого й чорного);
  · ворота тону (`ворота_тону`, C* 8): частка achromatic не зростає з хромою на жодному промені тону, при C* 0 —
    одна сім'я achromatic, від C* 20 achromatic у вердикт не входить;
  · `температура_сім_ї` — None, коли хрома в межах порога помітності; тепліший (жовтіший) сірий — > 0, синіший — < 0.
Код виходу 1 — коли модуль суперечить сам собі (порушено хоч один інваріант).
Запуск із джерела/: python3 проби/колір_тон_сім_ї.py"""
import math, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import колір_тон as Т
from колір_простір_перетворення import lab_з_lch, to_lab

ЗНАЧНА = Т.РЕЄСТР["значна_сила"]["val"]
ДОПУСК_ПРОМЕНЯ = 0.02      # частка ядра: крок решітки 1 ΔE*ab міняє вузли, що входять у ядро


def сітка_srgb(кроків=8):
    """Lab вузлів куба sRGB: кроків³ кольорів з кінцями 0 і 255."""
    рівні = [round(255 * і / (кроків - 1)) for і in range(кроків)]
    return [to_lab((r, g, b)) for r in рівні for g in рівні for b in рівні]


def звірити_вердикт(lab, похибка, порушення):
    """Сили й вердикт однієї точки — проти рішень модуля."""
    сили = Т.сили_сімей(lab, похибка)
    значення = list(сили.values())
    if min(значення) < 0 or abs(sum(значення) - 1.0) > 1e-9 or значення != sorted(значення, reverse=True):
        порушення.append(("сили", lab, похибка, сили))
    вердикт = Т.сім_ї_кольору(lab, похибка)
    сім_ї = [(к, с) for к, с in сили.items() if к != Т.НЕВІДОМО]
    невідомо = сили.get(Т.НЕВІДОМО, 0.0)
    if not сім_ї or невідомо > сім_ї[0][1]:
        очікуване = [(Т.НЕВІДОМО, невідомо if сім_ї else сили.get(Т.НЕВІДОМО, 1.0))]
    else:
        очікуване = сім_ї[:2] if len(сім_ї) > 1 and сім_ї[1][1] >= ЗНАЧНА else сім_ї[:1]
    if вердикт != очікуване:
        порушення.append(("вердикт", lab, похибка, вердикт, очікуване))
    if Т.сім_я_кольору(lab, похибка) != вердикт[0]:
        порушення.append(("сім_я_кольору", lab, похибка))
    return вердикт


def головна():
    порушення, пар, невідомо, точок = [], 0, 0, 0
    for lab in сітка_srgb():
        for похибка in (0.0, 3.0):
            вердикт = звірити_вердикт(lab, похибка, порушення)
            точок += 1
            пар += len(вердикт) == 2
            невідомо += вердикт[0][0] == Т.НЕВІДОМО

    for L in range(0, 101, 5):
        вердикт = звірити_вердикт((float(L), 0.0, 0.0), 0.0, порушення)
        if [к for к, _ in вердикт] != ["achromatic"]:
            порушення.append(("вісь нейтралей", L, вердикт))

    променів = 0
    for L in (30, 50, 70):
        for h in range(0, 360, 15):
            променів += 1
            ахр = []
            for C in range(0, 25, 2):
                lab = lab_з_lch(float(L), float(C), float(h))
                вердикт = звірити_вердикт(lab, 0.0, порушення)
                ахр.append(Т.сили_сімей(lab).get("achromatic", 0.0))
                if C == 0 and [к for к, _ in вердикт] != ["achromatic"]:
                    порушення.append(("C* 0 не achromatic", L, h, вердикт))
                if C >= 20 and "achromatic" in [к for к, _ in вердикт]:
                    порушення.append(("achromatic від C* 20", L, h, C, вердикт))
            for і in range(len(ахр) - 1):
                if ахр[і + 1] > ахр[і] + ДОПУСК_ПРОМЕНЯ:
                    порушення.append(("achromatic зростає з хромою", L, h, 2 * і, ахр[і], ахр[і + 1]))

    поріг = Т.РЕЄСТР["поріг_помітності"]["val"]
    for lab in ((60.0, 0.0, 0.0), lab_з_lch(60.0, поріг * 0.9, 80.0), lab_з_lch(60.0, поріг * 0.9, 260.0)):
        if Т.температура_сім_ї(lab)[1] is not None:
            порушення.append(("температура без тону", lab, Т.температура_сім_ї(lab)))
    for h, знак in ((60, 1), (80, 1), (100, 1), (240, -1), (260, -1), (280, -1)):
        код, т = Т.температура_сім_ї(lab_з_lch(60.0, 4.0, float(h)))
        if код != "achromatic" or т is None or т * знак <= 0:
            порушення.append(("температура сірого", h, код, т))

    print(f"сітка sRGB 8³ × похибка 0/3: точок {точок}, пар {пар}, «невідомо» {невідомо}; "
          f"вісь L* 0–100 — 21; променів хроми {променів}")
    print(f"порушено інваріантів: {len(порушення)}")
    for п in порушення[:20]:
        print("  ", п)
    return 1 if порушення else 0


if __name__ == "__main__":
    sys.exit(головна())
