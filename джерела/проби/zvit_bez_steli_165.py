# -*- coding: utf-8 -*-
"""Рядок 165: стеля у звіті власника. Скільки знахідок віддав СУД проти того,
скільки їх лишилось у полі `знахідки` відповіді моста — тобто в колонці
`знахідки_коду` файла вердиктів і в `етапи.суд`. Друга пара чисел — мовний гейт
коду: скільки правил брудних і скільки з них доїхало у звіт.

Суд міряється незалежно від поля: обгортка над `pipeline.перевірити_від_моделі`
повторює ті самі кроки, що міст ДО стелі (`обмежити_вагу`, зняття `під_підлогою`,
відсів питань). 6 сцен `стенд_знімок` × руки 1 і 2.
Запуск із теки `джерела`: python3 проби/zvit_bez_steli_165.py"""
import sys, os, json, copy
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge as B, feed as Ф, pipeline as PL, реєстр_правил as РЕЄСТР, стенд_знімок as СЗ
СУД, _суд = [], PL.перевірити_від_моделі
def _лічба(*a, **k):
    в = _суд(*a, **k)
    зн = [z for z in РЕЄСТР.обмежити_вагу(copy.deepcopy(list(в.get("знахідки") or [])))
          if not z.pop("під_підлогою", False)]
    СУД.append(len([z for z in зн if not PL._питання_або_нуль(z)]))
    return в
PL.перевірити_від_моделі = _лічба

КАТ, База, зрізано = Ф.каталог_на_диску("каталог_повний.xml"), json.load(open("стенд_вх.json", encoding="utf-8")), 0
for назва, сцен in СЗ.СЦЕНАРІЇ.items():
    вх = dict(База, каталог=КАТ, сценарій=сцен, випадок=назва)
    з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    for рука, донор, пул in (("1", False, з["кандидати"]), ("2", True, з.get("кандидати_донора") or з["кандидати"])):
        ід = [(пул.get(с) or [{}])[0].get("id") for с in ("сукня", "взуття", "сумка", "прикраси", "пояс", "шарф")]
        СУД.clear()
        в = json.loads(B.виклик("від_моделі", json.dumps(
            dict(вх, донор=донор, ід=[x for x in ід if x]), ensure_ascii=False)))
        г = в.get("мовний_гейт_коду") or {}
        суд, звіт = (СУД[0] if СУД else -1), len(в.get("знахідки") or [])
        брудних, правил = int(г.get("брудних") or 0), len(г.get("правила") or [])
        зрізано += (суд != звіт) + (брудних != правил)
        print("%-22s рука %s · суд %3d → звіт %3d %s · мовний гейт брудних %d → правил %d %s"
              % (назва, рука, суд, звіт, "рівно" if суд == звіт else "ЗРІЗАНО",
                 брудних, правил, "рівно" if брудних == правил else "ЗРІЗАНО"))
print("ВИСНОВОК: зрізаних полів звіту — %d" % зрізано)
sys.exit(1 if зрізано else 0)
