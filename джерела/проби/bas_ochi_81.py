# -*- coding: utf-8 -*-
"""Рядок 81: вісь температури рангу основ бере знак і силу з b* ОЧЕЙ (тема-2 §6.1, Perrett 2023), не з
підтону шкіри (K-COND-02). Профіль стенда, очі карі #5a3a1e / світло-сині #7fa8d8 / сіро-зелені #759087 (смуга):
перші 8 рекомендованих (як бачить стенд) і 8 кольорових у ранзі ДО (старий фолбек `шкіра.тепло_сила`) і ПІСЛЯ,
скільки позицій змінилось; K-COND-02: ті самі очі, шкіра «засмагла»/«бліда» — знак, сила і вісь H по чипах
ті самі; зсув лише b* шкіри (±10) — та сама й кольорова вісімка; зсув L* рухає лише контраст (K-CLR-02).
Запуск із теки `джерела`: `python3 проби/bas_ochi_81.py`."""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import colorspace as cs, bridge as B, bases as ОС
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
def стара(F, сз, н):                      # фолбек до 20.09: знак і сила з підтону шкіри, надійність 0.15
    сила = (F.get("шкіра") or {}).get("тепло_сила")
    поз = max(-1.0, min(1.0, float(сила or 0.0) / 1.5)); return поз, abs(поз) * 0.15, "фото (0.15)"
нова = ОС._температура_людини
def ранг(шкіра, очі, стара_вісь=False):
    F = cs.features(cs.hx(шкіра), cs.hx(вх["волосся"][0]), cs.hx(очі))
    ОС._температура_людини = стара if стара_вісь else нова
    о = B._основи(F); ОС._температура_людини = нова
    усі = о["рекомендовані"] + о["інші"]
    return [x["ключ"] for x in о["рекомендовані"]], [x["ключ"] for x in усі if x["сім_я"] != "нейтраль"][:8], \
        {x["ключ"]: x["бал"] for x in усі}, о["пояснення"]["температура"], {x["ключ"]: x["осі"]["H"] for x in усі}
зм = lambda a, b: sum(1 for x, y in zip(a, b) if x != y)
for очі in ("#5a3a1e", "#7fa8d8", "#759087"):
    р0, к0, б0, _, _ = ранг(вх["шкіра"], очі, True); р1, к1, б1, т, _ = ранг(вх["шкіра"], очі)
    print("== очі %s: b* %.1f · позиція %+.2f · впевненість %.2f · %s" % (очі, cs.hx(очі)[2], т["позиція"], т["впевненість"], т["джерело"]))
    print("   рекомендовані 8 до:    " + " | ".join(р0[:8])); print("   рекомендовані 8 після: " + " | ".join(р1[:8]))
    print("   кольорові 8 до:    " + " | ".join(к0)); print("   кольорові 8 після: " + " | ".join(к1))
    print("   змінилось: у рекомендованій вісімці %d/8, у кольоровій %d/8, у ранзі %d/%d; max|Δбал| %.3f; "
          "склад рекомендованих: −%s +%s" % (зм(р0[:8], р1[:8]), зм(к0, к1), sum(1 for k in б0 if б0[k] != б1[k]), len(б0),
          max(abs(б0[k] - б1[k]) for k in б0), sorted(set(р0) - set(р1)), sorted(set(р1) - set(р0))))
    assert (max(abs(б0[k] - б1[k]) for k in б0) < 0.01) == (очі == "#759087")   # смуга: лише зняття старого ±0.003 зі шкіри
L, a, b = cs.hx(вх["шкіра"]); р, к, _, т, H = ранг(вх["шкіра"], "#5a3a1e")
for ім, ш in (("засмагла b*+10", cs.hex_з_lab((L, a, b + 10))), ("бліда b*−10", cs.hex_з_lab((L, a, b - 10))),
              ("засмагла L* 66", "#c9976a"), ("бліда L* 86", "#f0d2b6")):
    р2, к2, _, т2, H2 = ранг(ш, "#5a3a1e"); лише_b = "b*" in ім
    print("== K-COND-02, очі #5a3a1e, шкіра %s (%s): позиція %+.2f · вісь H по чипах та сама: %s · кольорова вісімка та сама: %s%s"
          % (ім, ш, т2["позиція"], H2 == H, к2 == к, "" if лише_b else " (зсув L* рухає лише контраст, K-CLR-02)"))
    assert т2["позиція"] == т["позиція"] == 1.0 and H2 == H and (к2 == к or not лише_b)
print("bas_ochi_81: зелено")
