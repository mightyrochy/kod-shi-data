"""М-1, В-4: ЧИ ДОХОДЯТЬ ДО ПАСПОРТА ПОЛЯ ПЕРЕКЛАДАЧА БЕЗ ОПОРИ В ЇЇ СЛОВАХ. П'ять ходів:
її слова, відповідь перекладача (дехто — з цитатами `quotes`/`quote`, дехто — з вигадкою) і
чесна розмітка «що вона справді сказала». Рахує поля паспорта, яких вона не казала
(вигадки, що дійшли), і її поля, які загубились. Лише `мовний_шар.паспорт_з_шару` — проба
та сама на main і на гілці. Запуск із `джерела`: python3 проби/шлях_шар_сторож.py"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import мовний_шар as МШ

ХОДИ = [  # (її слова, відповідь перекладача, поля паспорта, які вона справді назвала)
    ("Збери образ під цю спідницю і чоботи для походу на концерт",
     {"event": {"free_text": "похід на концерт"}, "place": "office_corporate", "hour": 7, "temperature_c": 30}, set()),
    ("ввечері о сьомій, надворі +6", {"hour": 19, "temperature_c": 6,
     "quotes": {"hour": "о сьомій", "temperature_c": "+6"}}, {"година", "темп_c"}),
    ("робочий день в офісі, business casual, без підборів",
     {"occasion": "work", "place": "office_corporate", "dress_code": "business_casual", "hour": 9,
      "temperature_c": 18, "duration_h": 9, "vetoes": [{"feature": "heels", "quote": "без підборів"}],
      "quotes": {"occasion": "робочий день", "place": "в офісі", "dress_code": "business casual"}},
     {"нагода", "місце", "дрес_код", "вето"}),
    ("театр на шосту вечора, надворі мороз", {"occasion": "theatre", "hour": 18, "weather_feel": "frost",
     "quotes": {"occasion": "театр", "hour": "на шосту вечора", "weather_feel": "мороз"}}, {"нагода", "година", "темп_c"}),
    ("хочу щось яскраве, але не джинси", {"wants": [{"color_class": "bright", "quote": "яскраве"}],
     "vetoes": [{"item_type": "jeans", "quote": "не джинси"}], "registers": ["romantic"]}, {"бажання", "вето"}),
]
ПОЛЯ = ("нагода", "місце", "дрес_код", "година", "темп_c", "тривалість_год", "бажання", "вето", "реєстр_людини")
є = lambda п, к: bool([w for сп in п["вето"].values() for w in сп]) if к == "вето" else п.get(к) not in (None, "", [], "невідомо")
вигадано, загублено = 0, 0
for слова, в, її in ХОДИ:
    п = МШ.паспорт_з_шару(в, {}, None, None, слова_ходу=слова)["паспорт"]
    зайві = [к for к in ПОЛЯ if є(п, к) and к not in її]
    нема = [к for к in її if not є(п, к)]
    вигадано, загублено = вигадано + len(зайві), загублено + len(нема)
    print("«%s» → вигадки в паспорті: %s · її загублене: %s" % (слова[:44], зайві or "—", нема or "—"))
    for р in п.get("не_взято_кодом") or []:
        print("   не взято: %s" % р[:150])
print("ПІДСУМОК: вигадок перекладача в паспорті %d · її полів загублено %d (ходів %d)" % (вигадано, загублено, len(ХОДИ)))
