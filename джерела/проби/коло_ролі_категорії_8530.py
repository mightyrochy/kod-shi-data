"""КОЛО-РОЛІ-3 (наряд 2.1-В, рядок 8530): межі категорій тону насичених — зі статистики назв крамниць (п.9), раз.
Виміри каталогу (`не_вимір` None) з C* > 34 і словом крамниці з восьми основних; для сусідніх за медіаною слів межа — тон
рівної помилки: частка першого слова за межею дорівнює частці другого перед нею (не середина медіан: розкиди слів різні).
Друкує медіани, межі й `колір_відношення.МЕЖІ_КАТЕГОРІЙ` поруч. Запуск із джерела/: python3 проби/коло_ролі_категорії_8530.py"""
import json, sys, math, statistics as S; sys.path.insert(0, ".")
import bridge as B, colorspace as cs, колір_річ as КР, колір_відношення as КВ
СЛОВА = ("рожевий", "червоний", "помаранчевий", "жовтий", "зелений", "блакитний", "синій", "фіолетовий")
B.виклик("запити", open("стенд_вх.json", encoding="utf-8").read())
тони = {с: [] for с in СЛОВА}
for x in B.каталог_останнього_пакета():
    с = (x.get("колір_назва") or "").strip().lower()
    if с in тони and КР.межі_кольору(x) and КР.не_вимір(x) is None:
        L, C, h = cs.lch(tuple(x["lab"]))
        if C > 34: тони[с].append(h)
def медіана(хх):
    з = math.degrees(math.atan2(sum(math.sin(math.radians(h)) for h in хх), sum(math.cos(math.radians(h)) for h in хх)))
    return (з + S.median(((h - з + 180) % 360) - 180 for h in хх)) % 360
м = sorted(((медіана(хх), с) for с, хх in тони.items() if хх))
print("медіани:", "  ".join("%s %.1f (n%d)" % (с, ц, len(тони[с])) for ц, с in м))
for (ц1, с1), (ц2, с2) in zip(м, м[1:] + м[:1]):
    шир = (ц2 - ц1) % 360
    за = lambda с, ц, h: ((h - ц + 180) % 360) - 180
    def помилка(t):   # t — зсув від ц1 у бік ц2
        return (sum(за(с1, ц1, h) > t for h in тони[с1]) / len(тони[с1]) - sum(за(с2, ц2, h) < t - шир for h in тони[с2]) / len(тони[с2]))
    t = min((i / 10 for i in range(0, int(шир * 10) + 1)), key=lambda t: abs(помилка(t)))
    print("  %-12s | %-12s середина %5.1f  рівна помилка %5.1f (%.0f %%)" % (с1, с2, (ц1 + шир / 2) % 360, (ц1 + t) % 360,
          100 * sum(за(с1, ц1, h) > t for h in тони[с1]) / len(тони[с1])))
print("МЕЖІ_КАТЕГОРІЙ:", КВ.МЕЖІ_КАТЕГОРІЙ)
