"""Заміщує процес і мережу, залишаючи справжні жнива, SQLite, зведення й стан обходу."""
import asyncio, csv, sys
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import AsyncMock, patch
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "zhnyvarka"))
import обхід, виконавець

def прогін(журнал, обрив=False, зі_зведенням=False):
    """Пропускає перервану крамницю або відновлює її справжнім HTML-шляхом виконавця."""
    а = SimpleNamespace(журнал=журнал, стеля=1, секунд_на_магазин=30, без_огляду=True,
                        оновити_перелік=False, пауза=0)
    збирач = виконавець.Виконавець(а)
    запущені = []
    async def картка(сторінка, рецепт, лічба, файл, адреса):
        """Зберігає відповідь і завершений запис замість мережевого запиту картки."""
        прохід = збирач.проходи[рецепт["домен"]]
        ід = прохід.відповідь(адреса, 200, b"<html>card</html>", кінцева=адреса)
        запис = dict(url=адреса, стан="картка", відповідь=ід)
        збирач._пиши(файл, запис); прохід.завершити(запис)
        лічба.update(картка=1, відкрито=1)
    def запустити(cmd, магазини, *межі):
        """Зберігає наслідок обриву однієї крамниці та виконує решту без мережі."""
        for домен in магазини:
            запущені.append(домен)
            if обрив and домен == "hang.com":
                continue
            рецепт = dict(домен=домен, сімейство="horoshop", транспорт="http", старт=f"https://{домен}")
            with patch.object(збирач, "_horoshop_адреси", AsyncMock(return_value=[f"https://{домен}/p1"])), patch.object(
                    збирач, "_картка", картка):
                asyncio.run(збирач._магазин(AsyncMock(), рецепт, asyncio.Semaphore(1)))
        return {д: (-1, True) if обрив and д == "hang.com" else (0, False) for д in магазини}
    ряд, читач = dict(нотатка="таймаут", карток="0", адрес_знайдено="0", відкрито="0"), обхід.останні_рядки
    with patch.object(обхід, "запустити_крамниці", запустити), patch.object(
            обхід, "останні_рядки", wraps=обхід.останні_рядки) as читати:
        if обрив and зі_зведенням:
            читати.side_effect = lambda *а: ({"hang.com": ряд, **читач(*а)[0]}, 1)
        обхід.main(["--журнал", журнал, "--магазини", "hang.com,ok.com", "--циклів", "1"])
    with open(Path(журнал) / "обхід_стан.tsv", encoding="utf-8") as файл:
        return {р["домен"]: р for р in csv.DictReader(файл, delimiter="\t")}, запущені
