# -*- coding: utf-8 -*-
"""Рядок 1620: чи ремонтує суддя K-CLR-02 (`колір_образу.біля_обличчя`) основи, які ранг (`bases.ранг`) сам
рекомендує. Профілі стенда ж1–ж8 (`аудит/проби/жінки`): ряд «рекомендовані» `міст_основи._основи` і п'ятірка
найвищих за балом; кожна основа — верхом біля обличчя. «Заміна» — суддя каже «вище» з ремонтом (не hint);
«аксесуар» — «нижче» з аксесуарним ремонтом; «навпаки» — ранг і суддя кажуть протилежне (перевищує ↔ нижче,
недобирає ↔ вище). Запуск із теки `джерела`: `python3 проби/осн1_ранг_суддя.py`."""
import sys, os, json, pathlib, collections
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import colorspace as cs, bridge as B, outfit as O, колір_образу as K
def суд(hx, ос):
    з = [z for z in K.біля_обличчя(O.елементи([dict(id="в", слот="верх", hex=hx)]), ос) if z.get("правило") == "K-CLR-02"]
    return ("ok" if з[0]["сила"] == "ok" else ("вище:" if "вищ" in з[0]["суть"] else "нижче:") + з[0]["сила"]) if з else "нема"
def рід(x, с):
    р = x["чому"].split("(")[1].split(" ")[0]          # напрям рангу: перевищує / недобирає / в міру
    return [н for н, т in (("заміна", с in ("вище:soft", "вище:strong")), ("аксесуар", с in ("нижче:soft", "нижче:strong")),
            ("навпаки", (р == "перевищує" and с.startswith("нижче")) or (р == "недобирає" and с.startswith("вище")))) if т]
разом = {"ряд": collections.Counter(), "п'ятірка": collections.Counter()}
for і in range(1, 9):
    ж = json.load(open("../аудит/проби/жінки/ж%d.json" % і, encoding="utf-8"))
    F = cs.features([cs.hx(х) for х in ж["skin"]], [cs.hx(х) for х in ж["hair"]], cs.hx(ж["eyes"]))
    ос, о = O.контраст_особи(F), B._основи(F)
    ряд = о["рекомендовані"]; топ = sorted(о["рекомендовані"] + о["інші"], key=lambda x: -x["бал"])[:5]
    рядок = []
    for ім, хх in (("ряд", ряд), ("п'ятірка", топ)):
        c = collections.Counter(н for x in хх for н in рід(x, суд(x["hex"], ос))); c["усього"] = len(хх); разом[ім].update(c)
        рядок.append("%s %d: заміна %d, аксесуар %d, навпаки %d" % (ім, len(хх), c["заміна"], c["аксесуар"], c["навпаки"]))
    з = sorted({(round(x["осі"]["L"]), "+".join(рід(x, суд(x["hex"], ос)))) for x in ряд if рід(x, суд(x["hex"], ос))})
    print("ж%d шкіра L*%.0f (%s) волосся→обличчя L*%.0f контраст %.1f · %s · смуги L* ряду %s · %s" % (і, ос["L_шкіри"],
          F["шкіра"].get("depth_band"), ос["L_обличчя"], ос["value_gap"], " · ".join(рядок),
          sorted({round(x["осі"]["L"]) for x in ряд}), з))
for ім, c in разом.items():
    print("усього %s: %d основ — заміна %d, аксесуар %d, навпаки %d" % (ім, c["усього"], c["заміна"], c["аксесуар"], c["навпаки"]))
