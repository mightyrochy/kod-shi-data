# -*- coding: utf-8 -*-
"""K-OUT-02 (довжина верхнього шару масштабується зі зростом).

ЧОМУ СЛІДУ НЕ БУЛО: правило — НЕПЕРЕРВНИЙ член рангу, і він дорівнює нулю для
зросту від 167.6 см угору. У стенді й тесті живого шляху жінка 168 см, тобто
рівно над смугою джерела: мовчання тут не дефект, а правильна відповідь.
ЩО ПОКАЗУЄ ПРОБА: той самий каталог, той самий сценарій, зріст 158 — і рядок
стоїть у `вердикт.образи[0].знахідки` силою, що росте з недобору зросту."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
# зріст нижче смуги джерела (167.6 см) — інакше правило мовчить, і це правильно
вх["зріст"] = 158
вх["сценарій"].update(темп_c=5, опади="ні")
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
к = з["кандидати"]
# річ береться з КАТАЛОГУ пакета, не лише з пулу: ознака, під яку писане правило,
# трапляється в 326 із 618 речей слота, і `перевірити_від_моделі` законно судить річ поза
# кандидатами (вона лише лягає в `поза_кандидатами`) — тим самим шляхом, яким у
# продукт заходить річ, знайдена моделлю в повному каталозі.
ціль = next(c for c in кат.values() if c.get("слот") == "верхній_шар" and (c.get("довжина_рівень") in ("литка", "максі")))
ід = [ціль["id"]] + [(к.get(сл) or [{}])[0].get("id") for сл in ("сукня", "взуття")
                     if (к.get(сл) or [])]
print("верхній шар:", ціль["назва"][:52])
print("ознака входу:", "зріст 158 см проти смуги джерела 167.6 · рівень «%s»" % ціль.get("довжина_рівень"))
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
р = next((z for z in (о.get("знахідки") or []) if z.get("правило") == "K-OUT-02"), None)
print("K-OUT-02 у вердикті:", "НЕМА" if not р else
      "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:62]))
print("речі рядка:", (р or {}).get("речі"), "· регістр", (р or {}).get("регістр"))
print("сила — неперервна, не бакет:", (р or {}).get("сила_нп"),
      "· джерело:", "недобір зросту до смуги")
