"""ФІГ-2, рядок 904: коди умов у заяві `body_knot` (`shared`/`own`) — чи мають визначення в словнику
виклику (`task.statement_codes`). Тіла: стенд + п'ять тіл `hypergraph.самоперевірка`. Шлях той, що в
промпті: `hypergraph.вузли_тіла` → `дріт_моделі.заяви` → `збирач_промптів.коди_заяв` → `визначення_заяв`.
Друкує по тілу: умови вузла · без визначення. Запуск із теки `джерела`."""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import fit as ПС, hypergraph as ГГ, дріт_моделі as Д, збирач_промптів as ЗП, внутрішня_мова as ВМ
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
тіла = {"стенд": (вх["зріст"], вх["обхвати"]),
        "168/98-92-72-100": (168, dict(плечі=98, груди=92, талія=72, стегна=100)),
        "160/92-88-78-110": (160, dict(плечі=92, груди=88, талія=78, стегна=110)),
        "172/110-104-80-96": (172, dict(плечі=110, груди=104, талія=80, стегна=96)),
        "164/100-96-90-102": (164, dict(плечі=100, груди=96, талія=90, стегна=102))}
for н, (зр, об) in тіла.items():
    T = ПС.тіло(float(зр), {k: float(v) for k, v in об.items()})
    в = ГГ.вузли_тіла(ГГ.ребра(T))
    if not в: print("%-18s вузла нема" % н); continue
    дріт = {"style_rules": Д.заяви(в["заява"])}
    сл = ВМ.визначення_заяв(ЗП.коди_заяв(дріт))
    зн = next(iter(дріт["style_rules"][0].values()))
    умови = list(dict.fromkeys(зн.get("shared", []) + зн.get("own", [])))
    print("%-18s умови %s · у словнику виклику %s · без визначення %s"
          % (н, умови, sorted(сл), [у for у in умови if not сл.get(у)]))
