import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
if len(sys.argv) > 1: sys.path.insert(0, sys.argv[1])
import colorspace as К, fit as Т, міст_основи as М, brief as Б
import формальність as Ф, композитор_придатні as П, суд_від_моделі as С
ознаки = К.features(К.hx("#deb295"), К.hx("#f1dbaa"), К.hx("#759087"))
тіло = Т.тіло(168, dict(плечі=98, груди=92, талія=74, стегна=99, високе_стегно=88))
речі = [dict(id="рюкзак", тип="рюкзак", слот="сумка"),
        dict(id="кеди", тип="кеди", слот="взуття"),
        dict(id="туфлі", тип="човники", слот="взуття"),
        dict(id="сукня", тип="вечірня_сукня", слот="сукня")]
for рівень in (None, 4, 6, 7, 9):
    сц = dict(ошатність=[рівень, рівень], _ошатність=[рівень, рівень], пора="день") if рівень else {}
    пакет = М.пакет(ознаки, тіло, 168, сц)
    бриф = Б.бриф(пакет, гілка=None)["правила"]
    підлога = [(р["правило"], з["values"]) for р in бриф for з in р.get("заява", []) if з.get("code") == "high_occasion_floor"]
    лиш, геть, смуга = П.поза_сценою(речі, сц)
    суд = С.нижче_смуги_образу([р["id"] for р in речі], {р["id"]: р for р in речі}, сц)
    дубль = [з["правило"] for з in С.доповнення_судді(речі, сц) if з["правило"] == "K-KOH-08"]
    print("рівень", рівень, "смуга", смуга, "бриф", підлога, "пул геть", [р["id"] for р in геть],
          "суд", [(з["правило"], з["сила"], з["речі"]) for з in суд], "дубль", дубль)
    пояснено = С.нижче_смуги_образу(["рюкзак"], {"рюкзак": речі[0]}, сц, [{"ід": "рюкзак"}])
    print("  пояснений рюкзак:", [(з["сила_нп"], з.get("пояснено")) for з in пояснено])
сукня = dict(річ="біла", слот="сукня", lab=(93, 0, 4), площа=0.6)
for назва, вхід in (("наречена", {}), ("гостя", dict(зарезервований_колір="near_white")),
                     ("запрошене біле", dict(зарезервований_колір="near_white", дрес_код="black_and_white")),
                     ("без кольору", dict(зарезервований_колір="near_white", речі=None))):
    е = dict(сукня)
    if назва == "без кольору": е.pop("lab")
    знахідки = Ф.нагода_палітра([е], нагода="весілля", **вхід)
    print(назва, [(з["правило"], з["сила"], з["регістр"], з.get("сила_нп"))
                  for з in знахідки if з["правило"] == "K-KOH-08"])
