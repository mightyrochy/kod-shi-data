"""Проба (рядок 2920): «Оціни мій вечірній образ» — чи доходить пора дня до сцени оцінки.
Перекладач питання дає `{question_about: look, question: {free_text}, part_of_day: evening}` (`сценарій_слів`);
з чату нагоду й годину могла назвати раніше — паспорт (`сценарій_паспорта`, як шле `сценарійПаспортаП`).
Друкує `оцінка_образу.сценарій_оцінки` (сценарій і звідки) і годину сцени суду (`_сцена` → `сценарій.з_показу`)
для чотирьох входів і чи суд бачить вечір (`суд_від_моделі._доповнення_судді`, K-KOH-06: година ≥ 17). Моделей не кличе. Запуск: cd джерела && python3 проби/оцінка_пора_2920.py"""
import os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import оцінка_образу as ОО  # noqa: E402
питання = {"question_about": "look", "question": {"free_text": "Оціни мій вечірній образ", "lang": "uk"}}
ВХОДИ = {
    "слова: part_of_day evening": (None, dict(питання, part_of_day="evening"), None),
    "слова: hour 19 + part_of_day evening": (None, dict(питання, hour=19, part_of_day="evening"), None),
    "екран «Робота» + слова evening": ({"нагода": "робота"}, dict(питання, part_of_day="evening"), None),
    "паспорт чату: нагода свято, година 19": (None, питання, {"нагода": "свято", "година": 19}),
}
for назва, (екран, слова, паспорт) in ВХОДИ.items():
    сц, звідки = ОО.сценарій_оцінки(екран, слова, паспорт)
    сцен, _ = ОО._сцена(сц, {})
    г = сцен.get("година")
    print("%-40s година=%s (%s) · сцена: година=%s · вечір у суді: %s" % (
        назва, сц.get("година"), звідки.get("година"), г, г is not None and int(г) >= 17))
