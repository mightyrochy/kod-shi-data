"""Л-6, ПІСЛЯ В-4/В-5/В-6 (PR #345): ті самі п'ять речей із запису 26.09 — на ЕКРАНІ ОЦІНКИ.
До (розмова, `проби/шлях_оцінка_окремо.py`, `шлях_оцінка_типове.py`): 5 окремих вердиктів, знахідок
про поєднання 0; картка «11:00, +18 °C» дає K-WEA-01; нагоди не було — «з умовою» на 5 з 5.
Після: `оцінка_образу.суд` — один образ крізь `перевірити_від_моделі`, сцена лише з названого.
Запуск із `джерела`: python3 проби/шлях_оцінка_екран_образ.py"""
import sys, json; sys.path.insert(0, '.')
import оцінка_образу as О, colorspace as cs
вх = json.load(open('стенд_вх.json'))
ОБРАЗ = [('ф1', 'жакет приталений', 'верхній_шар', '#7d7f63', 'хакі', 6),
         ('ф2', 'сорочка з драпуванням', 'верх', '#cfd8e3', 'блакитний', 5),
         ('ф3', 'шкіряна міні-спідниця трапеція', 'низ', '#6b1f2a', 'бордовий', 6),
         ('ф4', 'клатч плетіння', 'сумка', '#7a2230', 'бордовий', 6),
         ('ф5', 'ботильйони на підборах', 'взуття', '#e6dfd2', 'вершковий', 6)]
речі = [dict(ід=і, фото=і, назва=н, слот=с, колір=к, ошатність=о, в_образі=True,
             вимір=dict(lab=list(cs.hx(h)), hex=h, слово=к)) for і, н, с, h, к, о in ОБРАЗ]
for назва, екран in (("порожні поля екрана (як на записі: нагоди й погоди вона не казала)", {}),
                     ("названо: побачення, +18 °C", {"нагода": "побачення", "темп_c": 18})):
    с = О.суд(dict(вх, речі=речі, сценарій_оцінки=екран, крамниця=False))
    зн = с["суд"]["findings"]
    пари = [з for з in зн if len(set(з.get("речі") or [])) > 1]
    погода = [з["правило"] for з in зн if str(з.get("правило")).startswith("K-WEA")]
    ошатн = [з["правило"] for з in зн if str(з.get("правило")).startswith(("K-KOH", "K-OCC"))]
    вх_нема = [б["input"] for б in с["без_входу"] if б.get("input")]
    print("ЕКРАН ОЦІНКИ · %s:" % назва)
    print("  образ: %d речей одним судом; знахідок %d, із них про кілька речей одразу %d (%s)"
          % (len(с["образ"]), len(зн), len(пари), ", ".join(з["правило"] for з in пари)))
    print("  сцена суду: %s · знахідок погоди %d · ошатності %d · «без входу» кодом: %s"
          % (json.dumps(с["сцена"], ensure_ascii=False), len(погода), len(ошатн), вх_нема or "—"))
    print("  пунктів чеклістів пройдено/провалено: %d; «без входу» повним переліком у звіт: %d"
          % (len(с["пункти"]), len(с["без_входу"])))
print("→ до: 5 окремих вердиктів і 0 знахідок про пари; +18 °C з типової картки судилось як сказане.")
print("  після: один образ, пари судяться (K-COL-06 — два різні білі); без названої погоди й нагоди —")
print("  0 знахідок погоди й ошатності й чесне «без входу» кодом; назване — судиться.")
