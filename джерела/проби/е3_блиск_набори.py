"""Входи блиску й металів для звірки ваги: повний каталог і варіанти фінішу та бажань, без моделі."""
import gzip, json, os, pathlib

ФІНІШІ = ("полірований", "дзеркальний", "сатин", "матовий", "брашований", "оксидований")
БАЖАННЯ = ("золото", "срібло", "перли", "етно", "інші", "без прикрас")
ДРАП = (dict(метал="золото"), dict(метал="срібло"), None, dict(білий="вершковий"), dict(білий="оптичний"),
        dict(нейтралі="теплі"), dict(нейтралі="холодні"), dict(білий="оптичний", нейтралі="не бачу різниці"),
        dict(білий="вершковий", нейтралі="не бачу різниці"), dict(метал="золото", білий="оптичний"))


def вікна(список, розміри):
    """Кожне вікно заданих розмірів з кожного початку."""
    return [список[і:і + н] for н in розміри for і in range(len(список) - н + 1)]


def набори():
    """(назва, функція, args, kwargs): блиск — вікна блискучих речей; метали — вікна металів по колу."""
    import colorspace as Ц, outfit as О
    with gzip.open(pathlib.Path(os.environ['TMP']) / 'каталог.json.gz', 'rt', encoding='utf-8') as ф:
        к = json.load(ф)
    Fs = [Ц.features(Ц.hx(ш), Ц.hx(в), Ц.hx(о)) for ш, в, о in (("#deb295", "#f1dbaa", "#759087"),
          ("#e0b080", "#a0522d", "#8b6b3d"), ("#fbe0d0", "#2b2b2b", "#3a6ea5"))]
    бл = [р for р in к if (р.get('блиск') or 0) >= 1]
    for г in вікна(бл, (2, 3, 4, 5)):
        for веч in (False, True):
            yield '+'.join(str(р['id']) for р in г) + '@%d' % веч, 'блиск_бюджет', [О.елементи(г)], dict(вечір=веч)
    мет = sorted((р for р in к if р.get('метал')), key=lambda р: (р['метал'], str(р['id'])))
    по_колу = sorted(мет, key=lambda р: ([x for x in мет if x['метал'] == р['метал']].index(р), р['метал']))
    вар = [dict(р, полірування=ФІНІШІ[і % 6], площа=(0.02, 0.1)[і // 12 % 2], місце_стилістки=dict(біля_обличчя=("так", "ні")[і // 6 % 2]))
           for і, р in enumerate(по_колу)]
    for г in вікна(по_колу, (1, 3)) + вікна(вар, (1, 2, 3, 5)) + [г + [dict(г[0], id='дт', метал='двотонний')] for г in вікна(вар, (3,))]:
        назва, Е = '+'.join(str(р['id']) + str(р.get('полірування')) for р in г), О.елементи(г)
        for і, F in enumerate(Fs):
            for д, драп in enumerate(ДРАП):
                yield назва + '@F%dд%d' % (і, д), 'метали', [Е, F], dict(драп=драп, речі=г)
        for баж in БАЖАННЯ:
            for д, драп in enumerate(ДРАП[:2]):
                yield назва + '@' + баж + str(д), 'метали', [Е, Fs[1]], dict(драп=драп, речі=г, прикраси=баж)
    for р in к:
        yield str(р['id']) + '@золото', 'метали', [О.елементи([р]), Fs[1]], dict(речі=[р], прикраси='золото')
