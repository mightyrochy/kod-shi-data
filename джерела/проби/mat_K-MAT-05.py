import sys, pathlib, json, collections
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import feed as Ф, bridge as B, status as СТ

вх = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml"); вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
ОЗНАКИ = ("щільність", "щільність_гм2", "збіг_малюнка", "поведінка_в_русі",
          "вага_фурнітури", "катишки", "витягнутість", "стан", "знос", "каблук_стертий")
є = collections.Counter()
for c in кат:
    for п in ОЗНАКИ:
        if c.get(п) not in (None, "", [], {}):
            є[п] += 1
print("речей у каталозі пакета:", len(кат))
print("сигналів якості й стану знайдено:", dict(є) or "жодного з %d полів" % len(ОЗНАКИ))
обм = next((з for з in СТ.ОБМЕЖЕННЯ if з["id"] == "сигнали_якості_і_стану"), None)
print("у реєстрі обмежень:", (обм or {}).get("що", "НЕМА")[:92])
print("єдиний можливий вхід:", (обм or {}).get("знімається", "—")[:92])
assert not є and обм, (є, bool(обм))
