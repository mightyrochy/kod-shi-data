"""ЧИ ДІСТАЛА Б МОДЕЛЬ ТЕ, ЩО ЇЙ СПОДОБАЛОСЬ (рядок 200). П'ять позитивних образів «Ір» (як є або «саме
моє»): для кожної речі — чи є в пулі `запити` на main, у тому самому слоті, річ ТІЄЇ Ж сім'ї кольору
(`колір_річ.сім_я`; самі ід пулу — вибірка ~350 з 11 829, тож міра — сім'я, не ід). Схема не обрана (як
у її прогонах) і «нейтрали+акцент»; стенд без офісу, очі стенда, її слова нагоди, сіди 3 і 7. Окремо —
хроматичних речей у «верх» (вона просила «яскравий верх, не темний»). Запуск: cd джерела && python3 проби/pul_pozytyvnykh_200.py"""
import json, sys, pathlib
sys.path[:0] = [str(pathlib.Path(__file__).resolve().parent.parent), str(pathlib.Path(__file__).resolve().parent)]
import bridge as B, колір_річ as КР
from sklad_virdyktiv_200 import В
from sud_shem_200 import ПРОГУЛЯНКА, УРОК, вх0
сім = lambda c: КР.сім_я(c["lab"]) if (c or {}).get("lab") else "?"
for сід in (3, 7):
    for мітка, зм in (("без вибору", {}), ("н+а", dict(схема="нейтрали+акцент", гілка=2))):
        for п, прогони in ((ПРОГУЛЯНКА, "0"), (УРОК, "34")):
            вх = dict(вх0, паспорт=dict(п, намір="conventional"), вимоги=п["слова"], сід=сід, **зм)
            r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
            кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
            є = {(с, сім(кат.get(x["id"]))) for с, v in (r.get("кандидати") or {}).items() for x in v}
            хр = sum(1 for с, ф in є if с == "верх" and not ф.startswith(("нейтраль", "?")))
            рядки = []
            for прогін, рука, вердикт, склад in В:
                if прогін in прогони and ("ЯК Є" in вердикт or "САМЕ" in вердикт):
                    речі = [кат["ж-" + i] for i in склад.split()]
                    нема = ["%s:%s" % (р["слот"], сім(р)) for р in речі if (р["слот"], сім(р)) not in є]
                    рядки.append("%s·р%d %d/%d%s" % (прогін, рука, len(речі) - len(нема), len(речі),
                                 (" (нема %s)" % ", ".join(нема)) if нема else ""))
            print("сід %d · %-10s · %-10s · сімей у «верх» хром. %d · %s" % (сід, мітка, п["слова"][:10], хр, " · ".join(рядки)))
