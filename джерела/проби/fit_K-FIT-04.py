# -*- coding: utf-8 -*-
"""K-FIT-04 (посадка пояса — головний важіль пропорції нога/тулуб).

ДО ПРАВКИ: у коді під цим ID не було НІЧОГО. Єдина числова гілка порівнювала
коефіцієнт ноги з популяційною нормою 0.480 і знята 07.09.2026 разом із самою
нормою — правильно, джерела під нею не було. Але знято було й ціле правило, хоч
його твердження норми не потребує: воно внутрішньоособове. І вхід у картці Є й не
читався ніким — param `посадка` стоїть на 597 низах із 2 032 (29.4 %).
ПІСЛЯ: правило каже одне, і без жодної норми — важіль працює, доки пояс ВИДНО.
Верх, що висить нижче за пояс, ховає його цілком: око починає ноги від краю верху,
і «висока посадка» в картці не міняє нічого. Проба показує обидва боки: верх
завдовжки «стегно» гасить важіль, верх завдовжки «талія» — ні."""
import sys, pathlib, json, collections
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, fit as ПС

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
низи = [c for c in кат if c.get("посадка")]
T = ПС.тіло(float(вх["зріст"]), {k: float(v) for k, v in вх["обхвати"].items()})
print("низів із посадкою в пакеті %d %s · висота пояса «висока» %.0f см, «середня» %.0f см"
      % (len(низи), dict(collections.Counter(c["посадка"] for c in низи)),
         ПС._висота_пояса(T, "висока"), ПС._висота_пояса(T, "середня")))
низ = next(c for c in низи if c["посадка"] == "висока")
взут = next(c for c in кат if c.get("слот") == "взуття")
for рівень in ("стегно", "талія"):
    верх = next(c for c in кат if c.get("слот") == "верх" and c.get("довжина_рівень") == рівень)
    о = ((json.loads(B.виклик("від_моделі", json.dumps(
        dict(вх, ід=[низ["id"], верх["id"], взут["id"]]), ensure_ascii=False))
        ).get("вердикт") or {}).get("образи") or [{}])[0]
    z = next((x for x in (о.get("знахідки") or []) if x["правило"] == "K-FIT-04"), None)
    print("  верх до «%s» → %s" % (рівень, "нема (пояс видно, важіль працює)" if not z
          else "%s %.2f · %s" % (z["сила"], z["сила_нп"], z["суть"][:64])))
    if рівень == "стегно":
        assert z, "верх нижче за пояс мусить гасити важіль — і правило мусить це сказати"
    else:
        assert not z, "верх до талії пояса не ховає: правило мусить мовчати"
