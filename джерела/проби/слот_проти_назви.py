# -*- coding: utf-8 -*-
# Рядки 152, 176, 177, 178 (Л-15). ФАКТ: скільки речей стоять у слоті за НАЗВОЮ там,
# де оголошення крамниці казало інше, і скільки назв СИРОГО каталогу втрачають
# дво-/трилітерний код моделі — по крамницях, щоб видно було, що чіпнуто лише ту, яка
# кодами й пише. «ремінець» цілі не має: він НЕ РІЧ, і перевіряється, що жодна назва
# з ним не робить річ поясом. Числа «до» — у тілі PR.
import os, re, sys, gzip, collections
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed, фід_слот as фс, назва_речі as НР
offers = feed.читати_yml(sys.argv[1] if len(sys.argv) > 1 else feed.каталог_на_диску())[0]
слоти = [feed.слот(o) for o in offers]
предмет = lambda o: фс.предмет_назви(фс.назва_суду(o).lower())
print("оферів у чистому каталозі: %d\nРЯДОК 176 — форма речі в назві переважує "
      "категорію крамниці:" % len(offers))
for ярлик, слова, чекаю in (("крос-боді", фс.ПАСТКИ_ПІДРЯДКА["боді"], "сумка"),
                            ("хайтоп", ("хайтоп",), "взуття"),
                            ("ремінець (деталь)", фс.ПАСТКИ_ПІДРЯДКА["ремін"], None)):
    є = [(с, o) for с, o in zip(слоти, offers)
         if any(x in фс.назва_суду(o).lower() for x in слова)]
    c = collections.Counter(с for с, _ in є)
    print("  %-18s назв %3d · у «%s» %s · назва дає «пояс» %d · слоти %s"
          % (ярлик, len(є), чекаю or "—", c[чекаю] if чекаю else "—",
             sum(1 for _, o in є if (предмет(o) or ("",))[0] == "пояс"), dict(c)))
опис = [(с, o) for с, o in zip(слоти, offers)
        if ((o.get("параметри") or {}).get("назва_джерело") or "").lower() == "опис"]
гол = [(с, предмет(o)) for с, o in опис if предмет(o) is not None
       and len(фс.назва_суду(o).lower()[:предмет(o)[2]].split()) <= фс.СТЕЛЯ_СЛІВ_ГОЛОВИ]
print("РЯДКИ 152/177 — голова назви переважує `param тип`:\n  назва з опису %d · "
      "предмет у голові %d · слот = предмет назви %d"
      % (len(опис), len(гол), sum(1 for с, р in гол if с == р[0])))
сирий = gzip.open(os.path.join(os.path.dirname(feed.каталог_на_диску()), os.pardir,
                               "каталог_повний.xml.gz"), "rt", encoding="utf-8").read()
по_крамниці = collections.defaultdict(list)
for о in re.finditer(r"<offer\b.*?</offer>", сирий, re.S):
    н = re.search(r"<name>([^<]*)</name>", о.group(0))
    м = re.search(r"<url>https?://(?:www\.)?([^/<]+)", о.group(0))
    if н: по_крамниці[(м.group(1) if м else "?").lower()].append(НР.почистити(н.group(1)))
коди = {кр: НР.коди_моделі(нн) for кр, нн in по_крамниці.items()}
пара = lambda ф: {кр: sum(1 for н in нн if ф(н, коди[кр])) for кр, нн in по_крамниці.items()}
print("РЯДОК 178 — код моделі знімається за ознакою КРАМНИЦІ (СИРИЙ каталог):\n"
      "  крамниць із кодами: %s\n  назв почищено: %s\n"
      "  назв із токеном ПІСЛЯ (імена моделей — лишаються): %s"
      % ({к: len(v) for к, v in коди.items() if v},
         {к: v for к, v in пара(lambda н, к: НР.зняти_код_моделі(н, к) != н).items() if v},
         {к: v for к, v in пара(lambda н, к: НР._токени_коду(НР.зняти_код_моделі(н, к))).items() if v}))
