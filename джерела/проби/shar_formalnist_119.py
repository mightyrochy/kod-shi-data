# -*- coding: utf-8 -*-
"""Рядок 119: пул верхнього шару проти ошатності нагоди — і що бачить жінка, коли
придатної речі нема. На кожній сцені: смуга нагоди, чи слот у пулі, скільки речей,
скільки з них перетинаються смугою формальності (`формальність.інтервал_формальності`,
той самий свідок, що в `graph.зона`) зі смугою нагоди, типи і нота слота. На сцені «г»
пул порожній — тоді проба питає `від_моделі` й друкує рядок, який жінка побачить на
картці (K-WEA-01, регістр «питання»).
Запуск: PYTHONPATH=. python3 проби/shar_formalnist_119.py
"""
import json, collections
import bridge as B, формальність as Ф

баз = json.load(open("стенд_вх.json"))
СВЯТО = dict(нагода="свято", місце="приміщення", дрес_код="black_tie", година=19, темп_c=18)
СЦЕНИ = (("а свято·black_tie·18°C", СВЯТО, None, None),
         ("б офіс·business_casual·18°C", dict(нагода="робота", місце="офіс",
          дрес_код="business_casual", година=9, темп_c=18), None, None),
         ("в свято·black_tie·12°C", dict(СВЯТО, темп_c=12), None, None),
         ("г свято·black_tie·18°C · ошатність 10 · brief", СВЯТО, "каталог_brief.xml", [10, 10]))

for мітка, с, кат_ф, о in СЦЕНИ:
    вх = dict(баз, сценарій=с, випадок="проба")
    if кат_ф: вх["каталог"] = кат_ф
    if о: вх["паспорт"] = dict(с, ошатність=о, формат="приміщення")
    r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    кат = {(x.get("назва") or x.get("id")): x for x in B.каталог_останнього_пакета()}
    пак = json.loads(r["руки"]["1"])
    вш = (пак.get("пул") or {}).get("верхній_шар") or []
    д = о or Ф.сценарій(місце=с["місце"], нагода=с["нагода"], година=с["година"],
                        темп_c=с["темп_c"])["діапазон"]
    lo, hi = float(д[0]), float(д[1])
    пер = sum(1 for x in вш for l, h in [Ф.інтервал_формальності(кат.get(x.get("назва")) or {})]
              if l is not None and not (h < lo or l > hi))
    т = collections.Counter(x.get("тип") for x in вш)
    print("[%s] смуга %g–%g · слот у пулі %s · речей %d · у смузі %d · %s"
          % (мітка, lo, hi, "верхній_шар" in (пак.get("пул") or {}), len(вш), пер,
             ", ".join("%s %d" % t for t in т.most_common(6)) or "—"))
    print("   нота:", (пак.get("ноти_слотів") or {}).get("верхній_шар") or "— нема")
    if not вш and "верхній_шар" in (пак.get("слоти_випали") or []):
        ід = [next(x["id"] for x in кат.values() if x.get("слот") == сл) for сл in ("сукня", "взуття", "сумка")]
        в = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
        print("   на картку:", next((p["суть"] for p in (в.get("питання") or [])
                                     if p.get("правило") == "K-WEA-01"), "— K-WEA-01 мовчить"))
