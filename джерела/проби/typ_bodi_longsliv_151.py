# -*- coding: utf-8 -*-
# Рядок 151: «боді» й «лонгслів» не мали ТИПУ, а без типу `інтервал_типу` віддає
# (None, None) — сітчасте боді йшло у весільні 7–9 нарівні з вечірньою сукнею.
# «ДО» — той самий код зі знятими двома ключами: ні файлів, ні env.
import sys, os, collections
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import feed, фід_каталог as ФК, фід_слот as Ф, формальність as ФН
НОВІ = ("боді", "лонгслів")
БЕЗ = [(т, к) for т, к in Ф.ТИП_КЛЮЧІ if т not in НОВІ]
оф = lambda r: {"назва": r.get("назва"), "категорія": r.get("категорія"),
                "параметри": r.get("параметри") or {}}
def типи(кат, ключі):
    сп, сд, сі = Ф.ТИП_КЛЮЧІ, Ф._КЛЮЧІ_ТИПУ_З_СУКНЕЮ, Ф.ІМЕНА_ТИПІВ
    Ф.ТИП_КЛЮЧІ, Ф._ТИП_КЕШ = ключі, {}
    Ф._КЛЮЧІ_ТИПУ_З_СУКНЕЮ = list(ключі) + [("сукня_без_уточнення", ("сукн", "плать"))]
    Ф.ІМЕНА_ТИПІВ = frozenset([т for т, _ in ключі] + ["сукня_без_уточнення",
                                                      "костюм_повсякденний", "комплект"])
    try:
        return [Ф._тип_речі_обчислити(оф(r), r.get("слот")) for r in кат]
    finally:
        Ф.ТИП_КЛЮЧІ, Ф._КЛЮЧІ_ТИПУ_З_СУКНЕЮ, Ф.ІМЕНА_ТИПІВ = сп, сд, сі
кат = ФК._прочитати_каталог(feed.каталог_на_диску("каталог_повний.xml"), 0)["каталог"]
до, після = типи(кат, БЕЗ), типи(кат, Ф.ТИП_КЛЮЧІ)
print("каталог %d · БЕЗ ТИПУ %d → %d" % (len(кат), до.count(None), після.count(None)))
пари = collections.Counter((a, b) for a, b in zip(до, після) if a != b)
print("змінили тип %d · %s" % (sum(пари.values()), dict(пари)))
впало = sum(1 for a, b in zip(до, після) if b not in НОВІ and a != b)   # чужого не крадемо
for т in НОВІ:
    print("  «%s» речей %d · інтервал %s" % (т, після.count(т), ФН.інтервал_типу(т)[:2]))
    впало += (після.count(т) == 0) + (ФН.інтервал_типу(т)[0] is None)
# Ручний огляд 40 назв (п.10): «Крос-боді» через дефіс не стояла ні в пастках, ні в
# ключах сумки — і сумки діставали тип верху.
крос = collections.Counter(після[i] for i, r in enumerate(кат)
                           if "крос-боді" in (r.get("назва") or "").lower())
print("«крос-боді» %d · типи %s" % (sum(крос.values()), dict(крос)))
впало += крос["боді"]
# K-KOH-05 на весіллі 7–9: доти МОВЧАЛО (типу нема), тепер каже «нижче».
сцен = {"діапазон": (7, 9), "risk_posture": "neutral"}
зн = lambda т: [z for z in ФН.формальність_образу(
    [{"річ": "в1", "слот": "верх", "назва": "Боді з сітки", "тип": т},
     {"річ": "н1", "слот": "низ", "назва": "Штани", "тип": "штани"}], сцен)
    if z.get("правило") == "K-KOH-05"]
д, п = зн(None), зн("боді")
print("K-KOH-05 весілля 7–9 · сітчасте боді: %d → %d знахідок%s"
      % (len(д), len(п), (" · «%s»" % п[0]["суть"]) if п else ""))
print("ВПАЛО %d" % (впало + len(д) + (0 if п else 1)))
