print("суд «комфорт», туфлі 9 см: ДО %s · ПІСЛЯ %s" % tuple(
    [(з["правило"], з["сила"]) for з in СН.намір_комфорту(каблук, "conventional", в)] for в in (None, ["комфорт"])))
