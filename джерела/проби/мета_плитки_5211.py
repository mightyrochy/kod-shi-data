    піс = len(КП._придатні(кат, [], None, None, сцен=dict(сцен, мета_важливо=[плитка]))[0])
    print("пул «%s» (театр, ошатність 6–7): ДО %d речей · ПІСЛЯ %d (знято %d)" % (плитка, до, піс, до - піс))
