"""Рядок 5211: кожна плитка аркуша «Чого я хочу від образу» діє правилом з входом (п.4). На каталозі: ранг уваги
(тихо / помітно / зона живота при «звично»), пул (зручно — стеля каблука; строго — допуск смуги), суд (K-COL-01 і
K-FIT-04 — довша лінія; K-PER-00 — каблук; K-KOH-05 hard — строго). Друкує ДО (плитки нема) і ПІСЛЯ (плитка є)."""
import os, sys, collections
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as ФК, регістр_уваги as РУ, композитор_придатні as КП, колір_світлота as КС, fit, суд_намір as СН
кат = ФК._прочитати_каталог(feed.каталог_на_диску(), ліміт_фото=0)["каталог"]
речі = [r for r in кат if r.get("слот") in ("верх", "низ", "сукня", "пояс", "сумка", "сережки", "намисто", "взуття")]
def рух(мета, зони=None):     # скільки речей ранг уваги рушить назад (+) і вперед (−), за слотами «у зоні живота» / поза
    л = collections.Counter()
    for r in речі:
        р = РУ.ранг_уваги(r, мета, зони_мети=зони)
        if р: л[("зона" if r["слот"] in РУ.ЗОНА_МЕТИ_СЛОТИ["живіт"] else "поза") + ("+" if р > 0 else "−")] += 1
    return dict(л)
print("речей: %d · ранг уваги: звично %s · тихо %s · помітно %s · звично+живіт %s · помітно+живіт %s" % (
    len(речі), рух("лестити"), рух("приховати"), рух("експресія"), рух("лестити", ["живіт"]), рух("експресія", ["живіт"])))
