"""Звірка знімків ваги `формальність.py` ДО/ПІСЛЯ: склад тотожний, таблиці сирих і ефективних змін."""
import collections, gzip, json, sys


def main():
    """Склад, сила, регістр і блок тотожні; друк змін ваги до й після спільної стелі."""
    def читати(шлях):
        with gzip.open(шлях, 'rt', encoding='utf-8') as ф:
            return json.load(ф)
    до, після = map(читати, sys.argv[1:3])
    assert len(до) == len(після), (len(до), len(після))
    сирі, еф, підлога = collections.Counter(), collections.Counter(), collections.Counter()
    for д, п in zip(до, після):
        assert д[:8] == п[:8], (д, п)
        if д[8] != п[8]:
            сирі[д[2], д[5], д[8], п[8]] += 1
        if д[9] != п[9]:
            еф[д[2], д[5], д[9], п[9]] += 1
        if д[10] != п[10]:
            підлога[д[2], д[10], п[10]] += 1
    print('знахідок', len(до), '— склад, сила, регістр і блок тотожні; сирих змін',
          sum(сирі.values()), '· ефективних', sum(еф.values()), '· підлоги', sum(підлога.values()))
    for назва, т in (('Сирі (до спільної стелі)', сирі), ('Ефективні (після `обмежити_вагу`)', еф)):
        print('\n%s\n\n| Правило | Сила | ДО | ПІСЛЯ | Кількість |\n|---|---|---|---|---|' % назва)
        for (правило, сила, було, стало), к in sorted(т.items(), key=str):
            print('| %s | %s | %s | %s | %d |' % (правило, сила, було, стало, к))
    print('\nПідлога:', dict(підлога))


if __name__ == '__main__':
    main()
