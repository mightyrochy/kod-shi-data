# -*- coding: utf-8 -*-
"""Рядок 180: бажання з альтернативами («куртка чи жакет»), запереченням («не темний», «не чорна») і
«яскравий». Друкує, які типи знайдено серед перших 8, і колір перших 4 (назва, L*, C*): темна — L* < 40.
Запуск: cd джерела && PYTHONPATH=. python3 проби/bazhannia_180.py [тека_джерел]  (ДО — те саме на main)."""
import json, os, sys
Д = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.getcwd()
sys.path.insert(0, Д); os.chdir(Д)
import feed; feed.каталог_на_диску()
import bridge as B, різноманітність_пулу as R
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
слоти = {c.get("слот") for c in кат if c.get("слот")}
ФРАЗИ = ["яскравий верх куртка чи жакет не темний", "сукня, але не чорна", "джинси чи штани", "пальто або тренч"]
L = lambda r: float((r.get("lab") or (50,))[0])
for ф in ФРАЗИ:
    з = R.речі_бажання(ф, кат, {с: [] for с in слоти}, сід=3, n=8)
    if not з:
        print("ФАКТ · «%s» → речі не названо" % ф); continue
    рч = з["речі"]
    типи = sorted({r.get("тип") for r in рч})
    перші = рч[:4]
    темних = sum(1 for r in перші if L(r) < 40)
    чорних = sum(1 for r in перші if "чорн" in str(r.get("колір_назва") or ""))
    print("ФАКТ · «%s» → слоти %s, тип «%s» · типи серед перших 8: %s · перші 4: %s · темних (L*<40) %d, чорних %d"
          % (ф, "/".join(з["слоти"]), з.get("тип"), ", ".join(map(str, типи)),
             "; ".join("%s L%.0f C%.0f" % (r.get("колір_назва"), L(r), R._хрома(r)) for r in перші), темних, чорних))
