# -*- coding: utf-8 -*-
"""Рядок 166: стилістка — жінка в УСІХ текстах показу для людини.

Знімає з `показ.html` коментарі коду й HTML-коментарі (там чоловічий рід про
ші-стиліста лишається й нікому не показується) і шукає в решті чоловічі
форми «стиліст / стиліста / стилістові / стилістом»; жіночі («стилістка»,
«стилістці», «стилісткою») під регулярку не підпадають за побудовою. Виняток —
`ШІ_ДОВІДКА`: вона їде В ПРОМПТ МОДЕЛІ, а не на екран, і наряд лишає промпти як є.
ДРУГИЙ РЯДОК ВИВОДУ — УЗГОДЖЕННЯ ДІЄСЛОВА: «А це стилістка почув…» має жіночий
ІМЕННИК, і перша перевірка це пропускає (знайдено оком). Рядки про КОД із цієї
другої лічби зняті — код чоловічого роду законно.
Запуск: cd джерела && python3 проби/stylistka_166.py"""
import os, re, sys
ДЖЕРЕЛА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ЧОЛОВІЧЕ = re.compile(r"стиліст(а|у|ові|ом)?\b", re.I)
_п = lambda m: "\n" * m.group(0).count("\n")

т = open(os.path.join(ДЖЕРЕЛА, "показ.html"), encoding="utf-8").read()
усього = len(ЧОЛОВІЧЕ.findall(т))
т = re.sub(r"<!--.*?-->", _п, re.sub(r"/\*.*?\*/", _п, т, flags=re.S), flags=re.S)
у_коді = [(i, р.strip()[:100]) for i, р in enumerate(т.split("\n"), 1) if ЧОЛОВІЧЕ.search(р)]
видимі = [п for п in у_коді if "ШІ_ДОВІДКА" not in п[1]]
ДІЄСЛОВА = re.compile(r"\b(почув|зрозумів|обрав|вирішив|сказав|порадив|додав|запитав|"
                      r"склав|знайшов|побачив|взяв|дібрав|переказав|уточнив)\b", re.I)
# Підмет «код» часто стоїть РЯДКОМ ВИЩЕ: довгий рядок показу склеєний із
# кількох літералів («…що код знав…» + «що вирішив про кожну її відповідь…»).
# Тому вікно — рядок і два перед ним; вужче давало хибну знахідку на звіті.
_рядки = т.split("\n")
_про_код = lambda i: any("код" in _рядки[j].lower() for j in range(max(0, i - 3), i))
дієслова = [(i, р.strip()[:100]) for i, р in enumerate(_рядки, 1)
            if ДІЄСЛОВА.search(р) and not _про_код(i)]

print("показ.html · чоловічий рід «стиліст»: у файлі цілком %d · поза коментарями %d · "
      "у ВИДИМИХ рядках (без промпта моделі) %d" % (усього, len(у_коді), len(видимі)))
for i, р in у_коді:
    print("   %s рядок %d: %s" % ("ВИДИМЕ" if (i, р) in видимі else "промпт моделі —", i, р))
print("показ.html · чоловіче минулого часу поза рядками про код: %d" % len(дієслова))
for i, р in дієслова:
    print("   ВИДИМЕ рядок %d: %s" % (i, р))
sys.exit(1 if (видимі or дієслова) else 0)
