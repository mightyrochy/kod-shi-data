# -*- coding: utf-8 -*-
"""K-REG-06 (смуга формальності реєстру проти нагоди) на живому шляху. Запуск із
теки `джерела`: `python3 проби/reg_K-REG-06.py`.

Правило читає формальність НАГОДИ зі `сцен["діапазон"]` — того самого діапазону,
який рахує `сценарій`. Стенд дає «business_casual» = 5–6; провідний реєстр рок
живе на 1–4, смуги не перетинаються, і правило каже це `hint`-ом, а не
забороною: вихід за смугу — це high-low, а не помилка.

ЗБІЛЬШЕННЯ КАТАЛОГУ (PR #81, 18.09.2026, 10 770→12 426 речей): «низ»/«взуття»
реєстру «рок» бралися з `пул` стенда — того самого JSON, що йде моделі (K речей
на слот). На зрослому каталозі серед семплованих кандидатів слота «взуття»
жодного разу не траплялась річ із провідним реєстром «рок» (виміряно: низ 1,
взуття 0), і `assert низ and взуття` падав без входу для правила. Провідний
реєстр — властивість РЕЧІ (`реєстри.реєстр_речі`), а не пулу; проба тепер
шукає його по ВСЬОМУ каталогу (`bridge.каталог_останнього_пакета` — те саме
джерело, з якого пул лише семплує K на слот) і передає моделі знайдені id
НАПРЯМУ (`ід=[…]`, той самий шлях, що вже стоїть у `проби/out_K-OUT-36.py`),
а не номером пулу, якого річ поза пулом не має."""
import json, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B, реєстри as РЕ

вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["гілка"] = 0
B.виклик("запити", json.dumps(вх, ensure_ascii=False))  # будує й кешує пакет — звідти каталог_останнього_пакета()
кат = list(B.каталог_останнього_пакета())


def _провідний_реєстр(р):
    """Найсильніший реєстр речі — той самий рахунок, яким пул позначає
    кандидата полем «реєстр» (`pipeline._РЕ_кандидата`), тут — по будь-якій
    речі каталогу, а не лише по семплованому пулу."""
    в = РЕ.реєстр_речі(р)
    ранг = sorted(в["бали"].items(), key=lambda x: -x[1])
    return ранг[0][0] if ранг else None


низ = [c for c in кат if c.get("слот") == "низ" and _провідний_реєстр(c) == "рок"]
взуття = [c for c in кат if c.get("слот") == "взуття" and _провідний_реєстр(c) == "рок"]
print("речей реєстру «рок» у каталозі: низ %d, взуття %d" % (len(низ), len(взуття)))
assert низ, "у каталозі нема речі слота «низ» з провідним реєстром «рок» — правилу нема на чому показатись"
assert взуття, "у каталозі нема речі слота «взуття» з провідним реєстром «рок» — правилу нема на чому показатись"

речі = [низ[0]["id"], взуття[0]["id"]]
в = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=речі), ensure_ascii=False)))
о = в["вердикт"]["образи"][0]
зн = [z for z in о["знахідки"] if z["правило"] == "K-REG-06"]
print("провідний реєстр образу:", (в["вердикт"].get("реєстр") or {}).get("провідний"))
print("смуга реєстру «рок»:", РЕ.РЕЄСТРИ["рок"]["смуга"],
      "· дрес-код нагоди:", вх["сценарій"].get("дрес_код"))
print("K-REG-06 у вердикті:", [(z["сила"], z["сила_нп"], z["суть"][:80]) for z in зн])
assert зн and зн[0]["сила_нп"] > 0, о["знахідки"]
assert зн[0]["сила"] == "hint", "вихід за смугу — high-low, не заборона"
