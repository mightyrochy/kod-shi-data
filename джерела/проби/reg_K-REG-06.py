# -*- coding: utf-8 -*-
"""K-REG-06 (смуга формальності реєстру проти нагоди) на живому шляху. Запуск із
теки `джерела`: `python3 проби/reg_K-REG-06.py`.

Правило читає формальність НАГОДИ зі `сцен["діапазон"]` — того самого діапазону,
який рахує `сценарій`. Стенд дає «business_casual» = 5–6; провідний реєстр рок
живе на 1–4, смуги не перетинаються, і правило каже це `hint`-ом, а не
забороною: вихід за смугу — це high-low, а не помилка."""
import json, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B, реєстри as РЕ

вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["гілка"] = 0
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
пул = json.loads(r["руки"]["1"])["пул"]
низ = [р["н"] for р in пул["низ"] if р.get("реєстр") == "рок"]
взуття = [р["н"] for р in пул["взуття"] if р.get("реєстр") == "рок"]
print("речей реєстру «рок» у живому пулі: низ %d, взуття %d" % (len(низ), len(взуття)))
assert низ and взуття, "у пулі нема двох рок-речей — правилу нема на чому показатись"

речі = [низ[0], взуття[0]]
відп = json.dumps({"версія": "1", "образи": [{"ід": "о1", "речі": речі}]}, ensure_ascii=False)
в = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=відп), ensure_ascii=False)))
о = в["вердикт"]["образи"][0]
зн = [z for z in о["знахідки"] if z["правило"] == "K-REG-06"]
print("провідний реєстр образу:", (в["вердикт"].get("реєстр") or {}).get("провідний"))
print("смуга реєстру «рок»:", РЕ.РЕЄСТРИ["рок"]["смуга"],
      "· дрес-код нагоди:", вх["сценарій"].get("дрес_код"))
print("K-REG-06 у вердикті:", [(z["сила"], z["сила_нп"], z["суть"][:80]) for z in зн])
assert зн and зн[0]["сила_нп"] > 0, о["знахідки"]
assert зн[0]["сила"] == "hint", "вихід за смугу — high-low, не заборона"
