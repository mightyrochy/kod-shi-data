# -*- coding: utf-8 -*-
"""K-REG-02 (реєстр людини) на живому шляху. Запуск із теки `джерела`:
`python3 проби/reg_K-REG-02.py`.

До правки поле існувало з двох кінців і не мало середини: `перевірити_образ`
брав `kw.get("реєстр_людини")`, `сценарій.ПОЛЯ` його оголошував, а паспорт
випадку такого поля не мав — на живий шлях завжди приїжджав None. Після:
паспорт → `сценарій.з_показу` → kw → `реєстри.перевірити`, і правило говорить
обома голосами — знахідкою, коли реєстр названо, і чесним «входу нема», коли ні."""
import json, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B, реєстри as РЕ, реєстр_правил as R

ПАСПОРТ = dict(подія="робочий день в офісі", нагода="робота", місце="офіс", година=9,
               темп_c=18.0, дрес_код="business_casual", вето={}, бажання=[],
               настрій=[], невідомо=[])


def прогін(реєстр_людини):
    вх = json.load(open("стенд_вх.json", encoding="utf-8"))
    вх["гілка"] = 0
    вх["паспорт"] = dict(ПАСПОРТ, реєстр_людини=реєстр_людини)
    r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    пул = json.loads(r["руки"]["1"])["пул"]
    # образ СВІДОМО з чужих реєстрів: більше ніж одна цитата — саме те, що ловить K-REG-02
    н = [next(р["н"] for р in пул[с] if р.get("реєстр") and р["реєстр"] != "класика")
         for с in ("низ", "взуття")]
    відп = json.dumps({"версія": "1", "образи": [{"ід": "о1", "речі": н}]}, ensure_ascii=False)
    в = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=відп),
                                                    ensure_ascii=False)))
    return н, json.loads(r["руки"]["1"])["випадок"].get("реєстр_людини"), в


н, у_пакеті, в = прогін(["класика"])
зн = [z for z in в["вердикт"]["образи"][0]["знахідки"] if z["правило"] == "K-REG-02"]
print("людина назвала «класика» · реєстр_людини в пакеті для моделі:", у_пакеті)
print("образ із чужих реєстрів:", н)
print("K-REG-02 у вердикті:", [(z["сила"], z["сила_нп"], z["суть"][:70]) for z in зн])
assert у_пакеті == ["класика"] and зн and зн[0]["сила_нп"] > 0, (у_пакеті, зн)

# другий голос: людина не назвала нічого — правило мовчить ЧЕСНО, не тихо
зн0, _ = РЕ.перевірити([dict(назва="Жакет вовняний"), dict(назва="Штани карго")], R._зн)
без = [z for z in зн0 if z["правило"] == "K-REG-02"]
print("людина не назвала нічого:", [(z["сила"], z["сила_нп"], z["суть"][:60]) for z in без])
assert без and без[0]["сила"] == "питання" and без[0]["сила_нп"] == 0.0, зн0
print("тобто: знахідка є, у вердикт не йде (сила 0), а стоїть у черзі на вхід")
