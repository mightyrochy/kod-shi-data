# -*- coding: utf-8 -*-
"""НАМІР-2 (рядок 1435): чи мовна модель чує НЕЯВНИЙ намір — «я не хочу щоб вона знов щось сказала» (свекруха,
ювілей; ж1 і ж7 розбору 02.10) — і чи пул тоді без дози «на межі» (п.17: «приховати» / «не хочу виділятись» — без
дози). Той самий шов, що `намір1_чує.py`: `промпт_розмови` → жива модель → `прийняти_розмову` → `мова`. Доза — та сама
умова, що `композитор_збирання` (намір conventional без цитати наміру й мета не «приховати»). Друкує намір, мету,
цитату, ноту стилістці й «доза так/ні». Запуск: cd джерела && MODEL=<мовна модель> python3 проби/намір2_неявний.py
[номери через кому]; ZHYVA=sonnet — лише за рішенням менеджера; без моделі — лише список реплік."""
import json, os, sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); import мова_спільне as С; М = С.М
ВИПАДКИ = [  # (її слова, чекаю дозу: так | ні)
    ("ну короче в суботу ми йдемо до свекрухи на ювілей там буде ресторан і вся родина я не хочу щоб вона знов щось "
     "сказала", "ні"),
    ("ювілей свекрухи в ресторані, головне щоб без претензій, вона завжди до чогось чіпляється", "ні"),
    ("на весілля до двоюрідної сестри, там буде вся рідня, не хочу щоб потім пліткували", "ні"),
    ("корпоратив, буде директор, хочу щоб до мене не було жодних питань", "ні"),
    ("на зустріч, щоб не виділятись", "ні"),
    ("на ювілей до свекрухи в ресторан у суботу", "так"),
    ("на день народження подруги в кафе", "так"),
]
номери = [int(х) for х in sys.argv[1].split(",")] if len(sys.argv) > 1 else range(1, len(ВИПАДКИ) + 1)
підс = {"влучно": 0, "хибно": 0}
for н in номери:
    слова, чекаю = ВИПАДКИ[н - 1]
    if not С.МОДЕЛЬ: print("%2d %s" % (н, слова)); continue
    відп, с = С.модель(М.промпт_розмови({"розмова": {"нове": слова, "історія": []}, "сценарій": {}, "паспорт": {}}))
    р = М.прийняти_розмову(відп)
    п = json.loads(М.мова({"паспорт_з": р["внутрішня"], "сценарій": {}, "паспорт": {}, "слова_розмови": [слова],
                           "частини": р["частини"]}))["паспорт"]
    нам, мета = п.get("намір") or "conventional", п.get("мета") or "невідомо"
    доза = "так" if нам == "conventional" and мета != "приховати" and not str(п.get("намір_слова") or "").strip() else "ні"
    оц = "влучно" if доза == чекаю else "хибно"; підс[оц] += 1
    print("%2d %-7s доза чекаю %-3s маю %-3s | намір %-15s мета %-10s %.0fс | цитата: %s | нота: %s"
          % (н, оц, чекаю, доза, нам, мета, с, п.get("намір_слова") or "-", (п.get("пояснення_мови") or "-")[:120]))
print("РАЗОМ (%s): %s" % (С.МОДЕЛЬ, " · ".join("%s %d" % кв for кв in підс.items())))
