"""РЯДОК 198, КАНАЛ РЯДКА 157: її прохання про аксесуар, написане ПОЗА екраном сценарію.
Рядок 157 закрив цей канал для «В мене світлі джинси… врахуй їх при побудові образу», і
`_ВИМОГА` дістала «хочу» й «хотіла б». Але у файлі вердиктів «Ір» обидві її просьби про
аксесуар стоять у БЕЗОСОБОВІЙ формі: рука 4 — «Хотілось би шарф», рука 1 — «Хочеться
більше ремінців, шарфів чи кепок». Їх `_ВИМОГА` не знала, тож прохання лишалось питанням
до помічниці й у паспорт не йшло. Друга вада дзеркальна: `_МЕЖА_КЛАУЗИ` ділить речення
ПЕРЕД «хочу», тож у «Не хочу шарф» заперечення лишалось у попередній клаузі, і МЕЖА жінки
їхала в сценарій як ПРОХАННЯ про шарф. Запуск: cd джерела && python3 проби/prokhannia_poza_198.py"""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import річ_з_фото as РФ
ТРЕБА = [   # (репліка поза сценарієм, чи має піти в сценарій)
    ("Хочу шарф", True), ("Хотілось би шарф", True), ("Хотілося б кепку", True),
    ("Хочеться більше ремінців, шарфів чи кепок", True), ("Кортить шарф", True),
    ("Додай шарф до образу", True), ("Хочу сукню, але не хочу шарф", True),
    ("В мене світлі джинси кльош. Врахуй їх при побудові образу", True),
    ("Хочу, щоб було тепло — може, штани зі стрілками?", True),
    # її МЕЖА, чуже, питання й річ, якої зараз нема, — у сценарій НЕ йдуть
    ("Не хочу шарф", False), ("Не хочеться шарфа", False), ("Без шарфа, будь ласка", False),
    ("Чи підійде мені шарф?", False), ("А чому в образі джинси?", False),
    ("Як зав'язати шарф?", False), ("Що таке капсула?", False),
    ("Моя сестра має гарний шарф", False), ("Свої кросівки не беру", False),
    ("Мої джинси в пранні, тож візьми інші штани", False),
    ("Врахуй їх при побудові образу", False)]      # без предмета — нема чого враховувати
впало, її = [], []
for т, треба in ТРЕБА:
    д = РФ.довідка_репліка(т)
    if д["до_сценарію"] != треба:
        впало.append((т, д["до_сценарію"], треба))
    if т in ("Хотілось би шарф", "Хочеться більше ремінців, шарфів чи кепок", "Не хочу шарф"):
        її.append("«%s» → %s (%s)" % (т[:42], д["до_сценарію"], д["чому"][:46]))
print("ФАКТ · реплік %d · розбіжностей %d" % (len(ТРЕБА), len(впало)))
for т, є, треба in впало:
    print("   ✗ «%s» → %s, а треба %s" % (т, є, треба))
print("ФАКТ · її три випадки:\n   %s" % "\n   ".join(її))
assert not впало, "репліка поза сценарієм іде не туди"
