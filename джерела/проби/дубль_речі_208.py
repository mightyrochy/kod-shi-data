"""Рядок 208 · доповнення куратора: модель назвала одну річ в образі двічі. Що робить `від_моделі`
на пулі стенда (`стенд_вх.json`): падає чи судить річ один раз і називає зведення. Друкує факт.
Та сама проба на дереві main дає «до». Запуск: cd джерела && python3 проби/дубль_речі_208.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), варіантів=10, ремонт_варіантів=5,
          бюджет_символів=120000, без_фото=1)
пул = json.loads(json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["руки"]["1"])["пул"]
н = lambda с, k=0: пул[с][k]["н"]
д = lambda о: json.dumps(dict(версія="1", образи=[dict(ід="о1", речі=о, день="офіс"),
                                                 dict(ід="о2", речі=[н("сукня"), н("взуття", 1), н("сумка", 1)], день="офіс")]), ensure_ascii=False)
def суд(ім, **дод):
    try:
        в = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, **дод), ensure_ascii=False)))
    except Exception as e:
        return print("%-40s → ВИНЯТОК %s: %s" % (ім, type(e).__name__, str(e)[:90]))
    о = (в.get("образи") or [в])[0]
    бл = [б.get("код") for б in (о.get("блокери") or []) if isinstance(б, dict)]
    вд = ((в.get("вердикт") or {}).get("образи") or [{}])[0].get("речі") or [r.get("id") for r in в.get("речі") or []]
    print("%-40s → у суді %s · блокери %s\n%44s нормалізовано: %s" % (ім, вд, бл or "—", "",
          [x for x in (в.get("відповідь_нормалізовано") or []) if "двічі" in x] or "—"))
    return в
суд("ОБРАЗИ_V1: верх названо двічі", текст_моделі=д([н("верх"), н("низ"), н("взуття"), н("сумка"), н("верх")]))
суд("ОБРАЗИ_V1: комплект «/верх» і «/низ»", текст_моделі=д([н("комплект") + "/верх", н("комплект") + "/низ",
                                                           н("взуття"), н("сумка")]))
суд("проза «ОБРАЗ:» з тим самим номером двічі", текст_моделі="ОБРАЗ: " + ", ".join(
    [н("верх"), н("низ"), н("взуття"), н("сумка"), н("низ")]))
ід = (суд("без дубля (звідси склад для опису)", текст_моделі=д([н("верх"), н("низ"), н("взуття"), н("сумка")]))
      or {}).get("образи", [{}])[0].get("ід") or []
суд("склад `ід` із дублем (крок опису, будь-хто)", ід=ід + ід[:1])
