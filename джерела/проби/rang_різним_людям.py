# -*- coding: utf-8 -*-
"""П.1 наряду «вимір рангу»: чи РІЗНІ ряди «рекомендовані» в трьох людей.
Історична поломка (bridge.py:360-366): _основи рахувала підтон-поріг і
трьом різним людям давала один і той самий список. Тут — те саме на живому
`bridge._основи`, з реальним стенд_вх.json + два синтетичні профілі."""
import json, sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import colorspace as cs, bridge as B

вх = json.load(open("стенд_вх.json", encoding="utf-8"))
ПРОФІЛІ = [
    ("1 середня нейтральна (стенд_вх.json)", вх["шкіра"], вх["волосся"][0], вх["очі"]),
    ("2 світла холодна", "#eec2b0", "#e8d5b0", "#8a9bb0"),
    ("3 смаглява тепла", "#96632f", "#3a2a1a", "#4a3222"),
]

топ8 = {}
for назва, шк, вл, оч in ПРОФІЛІ:
    F = cs.features(cs.hx(шк), cs.hx(вл), cs.hx(оч))
    о = B._основи(F, intent="conventional")
    рек = о["рекомендовані"]
    L = (F.get("шкіра") or {}).get("L"); т = (F.get("шкіра") or {}).get("тепло_сила")
    print("\n=== профіль %s (L_шкіри=%.1f, тепло_сила=%.2f) ===" % (назва, L, т))
    по_смузі = {}
    for x in рек:
        см = x["ключ"].split("·")[-1]
        по_смузі[см] = по_смузі.get(см, 0) + 1
    print("  рекомендованих: нейтралі=%d колір=%d, по смугах хроми: %s"
          % (len(о["нейтралі"]), len(о["кольори"]), по_смузі))
    for x in рек[:5]:
        print("  %.3f  %-22s %s" % (x["бал"], x["hex"], x["чому"]))
    топ8[назва] = {x["ключ"] for x in рек[:8]}

назви = list(топ8)
print("\n=== перетин топ-8 між профілями ===")
for i in range(len(назви)):
    for j in range(i + 1, len(назви)):
        а, б = топ8[назви[i]], топ8[назви[j]]
        print("  %s ∩ %s: %d/%d" % (назви[i], назви[j], len(а & б), min(len(а), len(б))))
