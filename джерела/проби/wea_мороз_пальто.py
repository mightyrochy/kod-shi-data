"""П-6: у мороз важче пальто, а не четверта річ. `python3 проби/wea_мороз_пальто.py`.

Смуга −8…+2 просила 3,5 шару, і сукня з вовняним пальтом діставала «шарів замало»
силою 0,75; сукня + светр + КУРТКА ловилась тією ж лічбою штук — із хибним
діагнозом «додати шар» замість «взяти тепліше пальто». Тепер мапа просить 2,5, а
тепловість самого верху питає окремий рядок за міткою типу. Друкує знахідки
K-WEA-01 на чотирьох образах при −3 °C (мітку кладе `pipeline`, тут — руками)."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import outfit as O, суд_погода as СП, верхнє_погода as ВП

сукня = dict(id="с-1", слот="сукня", hex="#334455", назва="Сукня", матеріал="вовна", тип="сукня")
светр = dict(id="в-1", слот="верх", hex="#aabbcc", назва="Светр", матеріал="вовна", тип="светр")
верхи = dict(пальто=dict(тип="пальто"), куртка=dict(тип="куртка"), тренч=dict(тип="тренч"))
def верх(тип):
    р = dict(id="п-1", слот="верхній_шар", hex="#222222", назва=тип.capitalize(),
             матеріал="вовна", тип=тип, тип_верхнього=тип)
    тф = ВП.теплова_функція([р])      # рівно те, що кладе `pipeline.перевірити_образ`
    return dict(р, тепловий_внесок=тф["тепловий_внесок"], теплова_мітка=тф["тепло"])

смуга = next(d for lo, hi, d in O.ТЕМП_МАПА if lo <= -3 < hi)
print("мапа −8…+2: %g шару · %s" % (смуга["шари"], смуга["нота"]))
for назва, речі in (("сукня + пальто", [сукня, верх("пальто")]),
                    ("сукня + куртка", [сукня, верх("куртка")]),
                    ("сукня + светр + куртка", [сукня, светр, верх("куртка")]),
                    ("сукня + светр + тренч", [сукня, светр, верх("тренч")])):
    E = O.елементи(речі, стан="надворі")
    зн = [z for z in СП.погода(E, темп_c=-3.0, стан="надворі", речі=речі)
          if z["правило"] == "K-WEA-01"]
    внесок = next(р["тепловий_внесок"] for р in речі if р["слот"] == "верхній_шар")
    # K-OUT-20 — сусідній рядок про «майже ні / ні»: саме тому цей про них МОВЧИТЬ
    o20 = [z for z in ВП.теплові_знахідки(речі, темп_c=-3.0) if z["правило"] == "K-OUT-20"]
    print("%-23s (верх %.2f шару) → %s%s" % (назва, внесок,
          " + ".join("%s [%s %s]" % (z["суть"], z["регістр"], z["сила_нп"]) for z in зн) or "тихо",
          " | K-OUT-20: %s" % o20[0]["сила_нп"] if o20 else ""))
