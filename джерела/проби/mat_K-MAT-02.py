# -*- coding: utf-8 -*-
"""K-MAT-02 (контракт тканина–силует) — «БЕЗ ВХОДУ», і це ВИМІР, а не обережність:
`python3 проби/mat_K-MAT-02.py`.

Корпус САМ означує вісь «структуроване ↔ плинне» двома числами з опублікованим
протоколом: коефіцієнт драпування (Cusick 1965/1968, BS 5058, ISO 9073-9:2008) і
кількість вузлів складки. Жодного з них фід не несе. Лишається один операційний
біт, який тема-3 з усього фабричного шару визнає, — ткане чи трикотаж.
ЩО ДРУКУЄ ПРОБА, і чому цього НЕ досить для емітента: скільки в каталозі кроїв,
які МУСЯТЬ тримати форму; у скількох із них названо рід тканини; скільки з них
конфліктні — і самі назви цих конфліктних речей, з яких видно, що більшість
конфліктів хибні (мітка трикотажу прийшла з іншого слова). Правило, що
спрацьовує шість разів на 8 975 речах і помиляється в чотирьох із шести, гірше
за мовчання; половину контракту тримає K-MAT-01, і пункт 15 чекліста стоїть на ній."""
import sys, pathlib, json, collections
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import feed as Ф, bridge as B, outfit as O, silhouette as СЛ, verify as V
import суд_образу as СУД, status as СТ

вх = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml"); вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
СТРУКТУРНІ = {к for к, d in СЛ.КРОЇ.items()
              if max(list((d.get("форма") or {}).values())
                     + list((d.get("ease") or {}).values())) >= 1.40}
рід = lambda r: (r.get("рід_тканини_слово") or СЛ.рід_тканини(r.get("текстура"))
                 or V.рід_зі_слова(r.get("волокно") or "")["рід"]
                 or V.рід_зі_слова(r.get("матеріал") or "")["рід"])
лік, конфлікт = collections.Counter(), []
for r in кат:
    if O.крій_речі(r) not in СТРУКТУРНІ: continue
    лік["крій мусить тримати форму"] += 1
    рд = рід(r)
    лік["рід названо" if рд else "рід НЕ названо"] += 1
    if рд == "трикотаж":
        конфлікт.append("%s · %s" % (O.крій_речі(r), r["назва"][:52]))
print("структуровимогливих кроїв: %s" % dict(лік))
print("конфліктних (плинна тканина під кроєм, що тримає форму): %d" % len(конфлікт))
for к in конфлікт: print("   ", к)
print("два числа, яких корпус вимагає, у фіді:",
      "коефіцієнт драпування — нема · кількість вузлів — нема")
обм = next((з for з in СТ.ОБМЕЖЕННЯ if з["id"] == "драп_і_вузли"), None)
print("у реєстрі обмежень:", (обм or {}).get("що", "НЕМА")[:82])
пункт = next(p for p in СУД.ЧЕКЛІСТ_НАДЛИШКУ if "K-MAT-02" in p[2])
print("пункт %d чекліста звужено до того, що вміє провалити: «%s»" % (пункт[0], пункт[1]))
assert обм and len(конфлікт) < 10
