"""Рядки 1490–1491 (КОМПЛЕКТ-2): склад комплекту кодом; її блуза з фото під жакетом комплекту.
Друкує: склад комплектів каталогу за джерелом; суд «комплект + блуза» (невідомий склад, коди
розбору `set_parts` — тимчасовим файлом `ROZBIR_KODY`); `закріпити_в_образі` з її блузою з фото."""
import sys, os, json, pathlib, tempfile, collections
_К = pathlib.Path(__file__).resolve().parent.parent; sys.path.insert(0, str(_К))
import feed as Ф, суд_від_моделі as СМ, річ_з_фото as РФ, каталог_коди as КК
кат = {r["id"]: r for r in Ф._база_прогону(Ф.каталог_на_диску("каталог_повний.xml"), 0)["каталог"]}
наб = [r for r in кат.values() if r.get("набір") is True]
СК = getattr(СМ, "склад_комплекту", lambda r: ("шар" if СМ.комплект_з_шаром(r) else "блокер", "—"))
print("комплектів: %d · склад:" % len(наб), dict(collections.Counter("%s/%s" % СК(r) for r in наб)))
print("  з кодом розбору set_parts (файл поруч):", sum(1 for r in наб if КК.поля(r["id"]).get("set_parts")))
тмп = tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8")
json.dump({"kj": {"set_parts": [{"item_type": "jacket"}, {"item_type": "skirt"}]},
           "ks": {"set_parts": [{"item_type": "shirt"}, {"item_type": "trousers"}]},
           "kb": {"set_parts": [{"item_type": "bodysuit", "slot": "top"}, {"item_type": "trousers", "slot": "bottom"}]}}, тмп); тмп.close()
os.environ["ROZBIR_KODY"] = тмп.name
ДОД = [dict(id="i%d" % n, слот=с, назва=с, тип=с) for n, с in enumerate(("взуття", "сумка", "сережки"))]
def суд(ід, назва):
    речі = [dict(id=ід, слот="комплект", тип="костюм", назва=назва), dict(id="b", слот="верх", назва="блуза", тип="блуза")]
    б, м = СМ.структура_образу_заяви(речі + ДОД, None, dict(нагода="робота", темп_c=18))
    б = [т for т, _ in б if "подвоєн" in т]
    п = [z["бракує"] for z in м if z.get("без_входу")]
    return "блокер" if б else ("питання: " + п[0][:40]) if п else "без блокера"
for ід, назва, що in (("k0", "Світло-зелений костюм зі спідницею міді", "назва без половин"),
                      ("kj", "Костюм чорний", "розбір: jacket + skirt"),
                      ("ks", "МОДЕЛЬ №905 СІРИЙ", "розбір: shirt + trousers"),
                      ("kb", "Костюм графітовий", "розбір: bodysuit/top + trousers")):
    print("  %-26s «%s» + блуза → %s" % (що, назва[:22], суд(ід, назва)))
сл = {"її-ф1": dict(слот="верх", назва="блуза", власна=True, закріплена=True),
      "kp": dict(id="kp", слот="комплект", назва="Костюм двійка штани + піджак сірий"),
      "kc": dict(id="kc", слот="комплект", назва="Лляний костюм сорочка і палаццо"),
      "k0": dict(id="k0", слот="комплект", назва="Костюм чорний"),
      "t": dict(слот="верх", назва="топ"), "n": dict(слот="низ", назва="штани"), "s": dict(слот="взуття", назва="лофери")}
for склад in (["kp", "s"], ["kc", "s"], ["k0", "s"], ["kp", "t", "s"], ["kp", "n", "s"]):
    ід, зм = РФ.закріпити_в_образі(склад, сл)
    print("  її блуза + %-12s → %s · знято %s" % ("+".join(склад), ід, (зм or {}).get("знято")))
os.unlink(тмп.name)
