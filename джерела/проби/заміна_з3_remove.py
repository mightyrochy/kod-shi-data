import os, re, sys
sys.path.insert(0, os.getcwd())
import colorspace as cs, fit as ПС, повнота_образу as ПО, суд_від_моделі as СВ
T = ПС.тіло(168, dict(плечі=98, груди=92, талія=74, стегна=99, високе_стегно=88))
F = cs.features(cs.hx("#deb295"), cs.hx("#f1dbaa"), cs.hx("#759087"))
р = lambda i, с, h, н, т, **к: dict(id=i, слот=с, hex=h, назва=н, тип=т, **к)
кат = [р("светр", "верх", "#8a7f74", "Светр", "светр", верх_см=140, низ_см=95), р("штани", "низ", "#5b4e4d", "Штани", "штани", верх_см=100, низ_см=5),
       р("черевики", "взуття", "#22201e", "Черевики", "черевики", верх_см=10, низ_см=0), р("балетки", "взуття", "#e8d9c4", "Балетки", "балетки", верх_см=6, низ_см=0)]
с = ПО.склад_вибору(dict(ід="о1", речі=[x["id"] for x in кат]), {x["id"]: x for x in кат}, {}, ["балетки"])
print("склад після «прибрати балетки»:", с["ід"], "· прибрано:", с["прибрано"], "· знехтувано:", с["знехтувано"])
for назва, ід in (("до зняття", [x["id"] for x in кат]), ("після зняття", с["ід"])):
    в = СВ.перевірити_від_моделі(ід, F, кат, T, dict(нагода="робота", смуга_погоди="mild"))
    print("повний суд над складом %-13s знахідок: %d" % (назва, len(в.get("знахідки") or [])))
м = open("міст_відповіді.py", encoding="utf-8").read().splitlines()
for шаблон in (r'd = dict\(d, ід=list\(_вибір\["ід"\]\)', r'_ід_верх = ', r'в = _P\.перевірити_від_моделі\(_ід_верх'):
    print("міст_відповіді.py:%d · %s" % (next(i + 1 for i, л in enumerate(м) if re.search(шаблон, л)), шаблон.replace("\\", "")))
