"""Повний каталог і граничні входи розбір_відповідей / суд_інтерес для звірки ваги ДО → ПІСЛЯ."""
import gzip, itertools, json, os, pathlib, random

ПРОБИ = pathlib.Path(__file__).resolve().parent


def набори():
    """Віддати (назва, функція, args, kwargs): ті самі входи для ДО і ПІСЛЯ, без моделі."""
    import outfit as О
    with gzip.open(pathlib.Path(os.environ['TMP']) / 'е3_каталог.json.gz', 'rt', encoding='utf-8') as ф:
        каталог = json.load(ф)
    print('каталог', len(каталог), flush=True)
    низи = [р for р in каталог if р.get('слот') in ('низ', 'сукня')]
    верхні = [р for р in каталог if р.get('слот') in ('верхній_шар', 'верх')]
    інші = {с: [р for р in каталог if р.get('слот') == с] for с in ('взуття', 'сумка')}
    # свідомий розрив: ваги 0.01…1.0 × сила × (блокує) — те, що множник робить із готовою вагою
    розриви = [dict(правило='R-СИНТ', текст='навмисно', ід=None)]
    for нп in [i / 100 for i in range(0, 101)]:
        for сила in ('hint', 'soft', 'default', 'strong', 'питання'):
            for блок in (False, True):
                yield 'свідомий|%s|%s|%s' % (нп, сила, блок), 'застосувати_свідомі', [
                    [dict(правило='R-СИНТ', сила=сила, сила_нп=нп, блокує=блок, речі=['х'], регістр='репліка',
                          суть='с', чому='ч')], розриви, [dict(id='х', назва='х', слот='верх')]], {}
    # K-INT-04: вибірка образів з каталогу — тут нейтральні образи, де видалення оголить інтерес
    r = random.Random(7)
    for і in range(3000):
        образ = [r.choice(верхні)] + [r.choice(низи)] + [r.choice(інші[с]) for с in ('взуття', 'сумка')
                                                                         if інші[с] and r.random() < 0.7]
        yield 'образ%d' % і, 'крок_редагування', [образ], {}
        if і % 3 == 0:
            yield 'заглушка%d' % і, 'крок_заглушка', [образ], {}
