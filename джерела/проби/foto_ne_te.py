# -*- coding: utf-8 -*-
"""Рядок 44 БЕКЛОГ: 20 речей із фото, що ЗБІГАЄТЬСЯ з назвою (theoriginals.com.ua,
слаг файлу містить слово з назви — перевірено вручну, `dress1.jpg` = сукня
Valentina), і 5 з vilni.store, де всі 5 SKU діляться ОДНИМ і тим самим набором
фото (сайтова заглушка, не товар — доведено збігом URL). Синтетична модель, що
поводиться як жива (за зразком `тест_живого_шляху.py`): називає ТОЧНО ці 5 у
«фото_не_те» своїми номерами й мовчить про решту 20. Питання — чи код
(`pipeline.опис_відповідь_з_json`, `номери_речей`) резолвить номер у ТУ САМУ
річ, а не в чужу (02.09 вже було). Запуск: `python3 проби/foto_ne_te.py`."""
import sys, pathlib, json, collections
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import feed as F, pipeline as PL

offers, _ = F.читати_yml("каталог_повний.xml")
матч = [o for o in offers if o.get("магазин") == "theoriginals.com.ua" and o.get("фото")][:20]
# П'ЯТІРКУ БЕРЕМО З НАЙБІЛЬШОЇ ГРУПИ СПІЛЬНОГО ФОТО, А НЕ З ПОЧАТКУ СПИСКУ (27.09.2026,
# рядок 173). Доти стояло `[:5]` — перші п'ять речей крамниці. Фікстура відстала від
# каталогу: після чисток і поповнень перші п'ять діляться вже ДВОМА наборами, і проба
# падала на власному `assert`, не дійшовши до питання, яке ставить. Заглушка нікуди не
# ділась — її й досі ділять 167 речей; проба тепер шукає групу, а не позицію.
_вілні = [o for o in offers if o.get("магазин") == "vilni.store" and o.get("фото")]
_групи = collections.Counter(tuple(o["фото"]) for o in _вілні)
_заглушка = _групи.most_common(1)[0][0] if _групи else ()
не_те = [o for o in _вілні if tuple(o["фото"]) == _заглушка][:5]
assert len(не_те) == 5 and len({tuple(o["фото"]) for o in не_те}) == 1, \
    "п'ятірка мусить ділити ОДНЕ фото-заглушку (найбільша група: %d речей)" % _групи.most_common(1)[0][1]

усі = матч + не_те
кандидати = {"верх": [dict(id=o["id"], назва=o.get("назва"), слот="верх",
                           фото=list(o.get("фото") or [])) for o in усі]}
ном, коди = PL.номери_речей(кандидати)
н_ід = {і: "#%d·%s" % ном[і] for і in ном}

# синтетична модель: точно 5 «не те», нуль хибних, нуль пропусків за задумом
флаги = [н_ід[o["id"]] for o in не_те]
текст = json.dumps(dict(версія="1", текст="опис образу для жінки, речення без markdown.",
                        як_носити=[], фото_не_те=флаги), ensure_ascii=False)
р = PL.опис_відповідь_з_json(текст, кандидати=кандидати, каталог=None)

очікувані = {o["id"] for o in не_те}
отримані = set(р["фото_не_ті"])
хибні = отримані - очікувані
пропуски = очікувані - отримані
print("Заявлено моделлю (5 номерів):", флаги)
print("Резолвлено кодом у id:", sorted(отримані))
print("Хибних спрацювань (чужа річ або зайве): %d · %s" % (len(хибні), хибні))
print("Пропусків (не резолвилось узагалі): %d · %s" % (len(пропуски), пропуски))
print("Помилок протоколу на відповіді:", р["помилки"])
assert not хибні and not пропуски, "код підмінив або загубив річ — саме поломка 02.09"
print("ВИСНОВОК: код резолвить номер→річ коректно; живого спрацювання моделі це не перевіряє.")
