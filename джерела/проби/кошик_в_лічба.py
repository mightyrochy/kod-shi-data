ФРАЗА = lambda в: (isinstance(в, ast.Constant) and isinstance(в.value, str) and " " in в.value
                   and len(set(СЛ.findall(в.value))) >= 2)


def фрази(вузол, лише=None, присв=None, kw=None):
    """Літерали-фрази вузла без докстрінга, звужені до `лише` / `присв` / `kw` (див. модуль)."""
    тіло = вузол.body[1:] if (isinstance(вузол, ast.FunctionDef) and вузол.body and isinstance(вузол.body[0], ast.Expr)
                              and isinstance(вузол.body[0].value, ast.Constant)) else [вузол]
    гілки = tuple(тіло)
    if kw:
        гілки = [к.value for т in тіло for в in ast.walk(т) if isinstance(в, ast.Call)
                 for к in в.keywords if к.arg == kw]
    elif лише:
        гілки = [в for т in тіло for в in ast.walk(т) if isinstance(в, ast.Call) and isinstance(в.func, ast.Attribute)
                 and в.func.attr == "append" and isinstance(в.func.value, ast.Name) and в.func.value.id == лише]
    elif присв:
        гілки = [в.value for т in тіло for в in ast.walk(т) if isinstance(в, ast.Assign)
                 and any(isinstance(ц, ast.Name) and ц.id == присв for ц in в.targets)]
    # ЛІТЕРАЛ У ПОРІВНЯННІ — КЛЮЧ, А НЕ ФРАЗА (Ч-3). `рівень == "краще інша"` — код читає
    # своє ж слово як умову (це кошик Б, інша хвиля), а не пише його жінці. Без цього
    # відсіву проба рахувала б такий ключ за фразу на екрані.
    порівняні = {id(x) for т in гілки for в in ast.walk(т) if isinstance(в, ast.Compare)
                 for x in ([в.left] + list(в.comparators)) if ФРАЗА(x)}
    return [в.value for т in гілки for в in ast.walk(т) if ФРАЗА(в) and id(в) not in порівняні]


def лічити(таблиця, заголовок):
    """Надрукувати рядок на кожен вузол таблиці й вернути [фраз, слів] разом.

    Ключ із «+» — той самий файл, що вже стоїть у таблиці вище (словник не тримає двох
    однакових ключів); суфікс знімається перед відкриттям."""
    підсумок = [0, 0]
    print(заголовок)
    for ключ, імена in таблиця.items():
        файл = ключ.rstrip("+")
        вузли = {}
        for в in ast.walk(ast.parse(io.open(файл, encoding="utf-8").read(), filename=файл)):
            if isinstance(в, ast.FunctionDef):
                вузли[в.name] = в
            elif isinstance(в, ast.Assign):
                for ц in в.targets:
                    if isinstance(ц, ast.Name):
                        вузли[ц.id] = в
                    elif isinstance(ц, ast.Subscript) and isinstance(ц.value, ast.Name) and isinstance(ц.slice, ast.Constant):
                        вузли.setdefault("%s[%s]" % (ц.value.id, ц.slice.value), в)
        for ім in імена:
            ключ_, _, kw = ім.partition("#")
            ключ_, _, присв = ключ_.partition("=")
            ключ_, _, лише = ключ_.partition(":")
            ф_ = (фрази(вузли[ключ_], лише or None, присв or None, kw or None)
                  if ключ_ in вузли else [])
            слів = len({w.lower() for т in ф_ for w in СЛ.findall(т)})
            підсумок = [підсумок[0] + len(ф_), підсумок[1] + слів]
            print("  %-20s %-26s фраз=%-4d слів=%-4d%s" % (файл, ім, len(ф_), слів,
                                                           "" if ключ_ in вузли else " ?"))
    return підсумок


