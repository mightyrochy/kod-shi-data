# -*- coding: utf-8 -*-
"""Рядок 169: «або витягуємо фото замість заглушок, або прибираємо речі з каталогу» —
по крамницях: скільки речей ДО не мали показного фото, скільком його ВІДНУЛО перечитування
сторінки товару, скільки ПРИБРАНО з пулу рук 1–2. Мережі не потребує: міряє, що зробили з
фідом ДАНІ виміру (`каталог_показ.json.gz`, прилад `прилади/показне_фото.py`), і одразу
доводить дві речі, які й мали статись у коді, — що відновлена адреса СТАЛА першим кадром
картки і що прибрана річ справді не проходить відсів пулу.
Запуск із `джерела`: PYTHONPATH=. python3 проби/bez_zaglushky_169.py"""
import collections, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed as Ф, фід_фото as ФФ, пакет_моделі as ПМ
д = ФФ.читати_показ()
адреси, без = д.get("адреси") or {}, д.get("без_показу") or {}
оф = Ф.читати_yml(Ф.каталог_на_диску("каталог_повний.xml"))[0]
за_ід, крам = {o["id"]: o for o in оф}, lambda і: str(і).split("@")[-1]
сп, хо, зб = ФФ._спільні_фото(оф), ФФ._хости_крамниць(оф), Ф.читати_збагачення()
ряд = lambda o: ФФ.кадри_речі(o, сп.get(o.get("магазин")) or {}, хо, (зб.get(o["id"]) or {}).get("фото"))
перший = sum(1 for і, а in адреси.items()
             if і in за_ід and (ряд(за_ід[і]) or [None])[0] == а[0])
відсік = collections.Counter(ПМ._жорстке_відсічення(dict(за_ід[і], слот="верх", ціна=1))
                             for і in без if і in за_ід)
жінці = [і for і in без if str(без[і]).lower().find("код") >= 0 or "None" in str(без[і])]
print("вимір %s · каталог %s · речей %d · із показним фото %d"
      % (д.get("знято") or "—", д.get("каталог") or "—", д.get("речей") or len(оф), д.get("із_показним") or 0))
print("БЕЗ ПОКАЗНОГО ФОТО ДО: %d → ВІДНОВЛЕНО зі сторінки товару %d · ПРИБРАНО з пулу %d"
      % (len(адреси) + len(без), len(адреси), len(без)))
print("відновлена адреса стала ПЕРШИМ кадром картки: %d з %d" % (перший, len(адреси)))
print("прибране справді не проходить відсів пулу: %d з %d · причини: %s"
      % (sum(v for k, v in відсік.items() if k), len(без),
         "; ".join("%s ×%d" % (k, v) for k, v in відсік.most_common())))
print("рядків, показаних ЖІНЦІ на картці: %d (причина їде у звіт вердиктів, не на екран)" % len(жінці))
ряди = collections.Counter(крам(і) for і in list(адреси) + list(без))
print("\n%-24s %6s %6s %6s" % ("крамниця", "ДО", "віднов", "прибр"))
for м, n in ряди.most_common():
    в = sum(1 for і in адреси if крам(і) == м)
    print("  %-22s %6d %6d %6d" % (м, n, в, n - в))
