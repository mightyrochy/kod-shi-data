# -*- coding: utf-8 -*-
"""Технічне сміття фіду на картці: HTML-сутність у тексті крамниці й заглушка бренду в назві.
ДО — сирий архів каталогу як є; ПІСЛЯ — те, що з нього робить вхід каталогу (`чистка_каталогу`).
Запуск: cd джерела && python3 проби/nazvy_smittia_feedu.py"""
import gzip, os, re, sys, tempfile
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, назва_речі as НР, чистка_каталогу as ЧК

АРХІВ = next(ш for ш in (os.path.join(ТУТ, "..", "каталог_повний.xml.gz"),
                         os.path.join(ТУТ, "каталог_повний.xml.gz")) if os.path.exists(ш))
сирий = gzip.open(АРХІВ, "rt", encoding="utf-8").read()
оферів = [м.group(0) for м in ЧК._OFFER.finditer(сирий)]
чисті = [ЧК._розекранувати_сире(т) for т in оферів]
print("ФАКТ · оферів в архіві %d · несуть екрановану HTML-сутність: ДО %d → ПІСЛЯ %d · шарів знято %d"
      % (len(оферів), sum(1 for _, n in чисті if n), sum(1 for т, _ in чисті if ЧК._розекранувати_сире(т)[1]),
         sum(n for _, n in чисті)))

шлях = os.path.join(tempfile.mkdtemp(), "сирий.xml")
open(шлях, "w", encoding="utf-8").write(сирий)
оферти = feed.читати_yml(шлях)[0]
заглушки = НР.заглушки_бренду(оферти)
print("ФАКТ · заглушка бренду за ознакою поля (модальний кошик ≥%d× наступного, ≥%d речей): %s"
      % (НР.ПЕРЕВАГА_ЗАГЛУШКИ, НР.МІН_ЗАГЛУШКИ, заглушки or "нема"))
картки = НР.читати_назви_карток()
до = після = 0
хвости_до, хвости_після = {}, {}
for o in оферти:
    з = заглушки.get(str(o.get("магазин") or ""))
    for з_, лічба, куди in ((None, 0, хвости_до), (з, 1, хвости_після)):
        н = str(НР.назва_для_показу(o, картки, з_)["назва"] or "")
        х = re.search(r"\(([^()]{2,40})\)\s*$", н)
        if х:
            куди[х.group(1)] = куди.get(х.group(1), 0) + 1
        if з and з in н:
            до, після = до + (лічба == 0), після + (лічба == 1)
print("ФАКТ · речей, що показують заглушку бренду в назві: ДО %d → ПІСЛЯ %d" % (до, після))
print("ФАКТ · справжні бренди в дужках назви (топ-5): ДО %s → ПІСЛЯ %s"
      % (sorted(хвости_до.items(), key=lambda x: -x[1])[:5],
         sorted(хвости_після.items(), key=lambda x: -x[1])[:5]))
