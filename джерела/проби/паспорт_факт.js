/* Один писар показу: дотик, старий паспорт, типове, очищення й незмінність уривка. */
const fs = require('fs'), path = require('path'), vm = require('vm'), assert = require('assert');
const дж = path.resolve(__dirname, '..');
const {прочитатиДовідникJSON} = require(path.join(дж, 'показ_шаблон.js'));
const довідник = прочитатиДовідникJSON(дж);
const код = fs.readFileSync(path.join(дж, 'показ/бібліотека.js'), 'utf8')
  .split('function макіяжФормиП')[0].replace('__ДОВІДНИК_ПОКАЗУ__', довідник);
const контекст = vm.createContext({});
vm.runInContext(код, контекст);
const виконати = вираз => JSON.parse(vm.runInContext('JSON.stringify(' + вираз + ')', контекст));
vm.runInContext("подіяРукиП('місце', 'парк'); КАРТКА_ЗАПИТУ_П.місце.уривок = 'у парку'; подіяРукиП('місце', 'офіс');", контекст);
assert.deepStrictEqual(виконати('КАРТКА_ЗАПИТУ_П.місце'), {значення:'офіс', джерело:'hand', уривок:''});
vm.runInContext("записатиФактП(КАРТКА_ЗАПИТУ_П, 'місце', 'парк', 'default'); подіяРукиП('темп_c', 0);", контекст);
assert.strictEqual(виконати('КАРТКА_ЗАПИТУ_П.місце.значення'), 'офіс');
assert.strictEqual(виконати("типовеЧислоП('сц-темп')"), false);
vm.runInContext("подіяРукиП('темп_c', null)", контекст);
assert.strictEqual(виконати("типовеЧислоП('сц-темп')"), true);
assert.strictEqual(виконати("карткаДавньогоПаспортаП({тривалість_год: 3, джерело_полів: {тривалість_год: 'рука'}}).тривалість_год.джерело"), 'hand');
vm.runInContext("подіяРукиП('вето', {зони: ['руки']}); const межі = {зони: ['спина']}; записатиФактП(КАРТКА_ЗАПИТУ_П, 'вето', межі, 'hand'); межі.зони.push('ноги');", контекст);
assert.deepStrictEqual(виконати('КАРТКА_ЗАПИТУ_П.вето.значення'), {зони:['спина']});
assert.strictEqual(виконати("ОПИС_ПОЛІВ_П.нагода.довідник"), 'нагоди');
console.log('Писар показу: уривок знято; слабший запис відхилено; 0 і null різняться; вкладені значення незалежні.');
