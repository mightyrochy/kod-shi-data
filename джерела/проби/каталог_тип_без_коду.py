# Рядок 6755: у скількох речах еталону 404 назва називає тип, якого нема в переліку `item_type` розбору, і що на них казала модель.
# «точний_тип» речі — код, який вона мала б дістати (очима, за назвою); перелік — `каталог_розбір._коди("item_type")`.
# Запуск: python3 -I джерела/проби/каталог_тип_без_коду.py [розбір.json ...]   (~1 с; моделі й каталогу не треба)
import sys, os, json, collections as C
Т = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.dirname(Т))
import каталог_розбір as КР, внутрішня_мова as ВМ
Е = json.load(open(Т + '/еталон_розбору.json', encoding='utf-8')); перелік = set(КР._коди('item_type'))
РЗ = [json.load(open(ф, encoding='utf-8')) for ф in sys.argv[1:]]
названі = [р for р in Е['речі'] if р.get('точний_тип')]; без = [р for р in названі if р['точний_тип'] not in перелік]
print('перелік item_type: %d кодів · речей, де назва називає тип: %d · з них коду в переліку нема: %d' % (len(перелік), len(названі), len(без)))
for р in названі:
    сказали = [к.get(р['id'], {}).get('item_type') for к in РЗ]
    print('  %-8s потрібен %-9s %-3s модель: %s' % (р['id'].split('@')[0], р['точний_тип'], 'є' if р['точний_тип'] in перелік else 'НЕМА', dict(C.Counter(сказали)) if РЗ else '-'))
print('слотів без жодного коду типу у `СЛОТ_ТИПУ`: %s' % (sorted(с for с in ВМ.ТАБЛИЦЯ['slot'] if с not in ВМ.СЛОТ_ТИПУ.values()) or 'нема'))
