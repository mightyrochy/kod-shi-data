# Рядок 194: `предмет_назви` шукала ключ ОДНИМ `find` і фільтрувала прикметник на
# нього. Коли ПЕРШЕ входження прикметникове, ключ кидався ЗОВСІМ — навіть якщо далі
# в назві він стоїть іменником. `_ключ_іменником` (рядок 184, той самий фільтр)
# шукає далі. Тепер обидва місця — «ключ як іменник» — це одна функція, а не дві.
import sys, os, collections, importlib.util
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import feed, фід_каталог as ФК, фід_слот as НОВ
_сп = importlib.util.spec_from_file_location(
    "до_фід_слот", os.environ.get("DO_FID_SLOT", "/tmp/194/до_фід_слот.py"))
СТАР = importlib.util.module_from_spec(_сп); _сп.loader.exec_module(СТАР)
кат = ФК._прочитати_каталог(feed.каталог_на_диску("каталог_повний.xml"), 0)["каталог"]
оф = lambda r: {"назва": r.get("назва"), "категорія": r.get("категорія"),
                "параметри": r.get("параметри") or {}}
низ = lambda r: (r.get("назва") or "").lower()
пр = [(r, СТАР.предмет_назви(низ(r)), НОВ.предмет_назви(низ(r))) for r in кат]
слоти = [(r, СТАР.слот(оф(r)), НОВ.слот(оф(r))) for r in кат]
різн_пр = [x for x in пр if (x[1] or (None,))[0] != (x[2] or (None,))[0]]
різн_сл = [x for x in слоти if x[1] != x[2]]
print("каталог %d · предмет_назви інший у %d · СЛОТ інший у %d"
      % (len(кат), len(різн_пр), len(різн_сл)))
print("переходи слота:", dict(collections.Counter("%s→%s" % (a, b) for _, a, b in різн_сл)) or "—")
# ЩО САМЕ ЗАКРИТО, І ЯК ЧАСТО ВОНО ТРАПЛЯЄТЬСЯ НА ЦЬОМУ КАТАЛОЗІ.
ключі = [(с, k) for с, кк in list(НОВ.СЛОТ_КЛЮЧІ) + list(НОВ.ПІД_СЛОТИ_ПРИКРАС) for k in кк]
скинуто, вдруге = collections.Counter(), []
for r in кат:
    н = низ(r)
    for _с, k in ключі:
        п = н.find(k)
        if п < 0 or not НОВ._ПРИКМЕТНИК.match(н[п + len(k): п + len(k) + 3]): continue
        скинуто[k] += 1
        if НОВ._ключ_іменником(н, k) >= 0: вдруге.append((r.get("назва"), k))
print("перше входження прикметникове (старий код кидав ключ): %d · %s"
      % (sum(скинуто.values()), dict(скинуто.most_common(4))))
print("з них ключ ДАЛІ стоїть іменником: %d%s"
      % (len(вдруге), (" · «%s» ключ «%s»" % (вдруге[0][0][:56], вдруге[0][1])) if вдруге else ""))
# Побудований випадок: назва, у якій ключ є ЛИШЕ прикметником, а потім іменником.
зр = "джинсова тканина 100% джинс"
д, п = СТАР.предмет_назви(зр), НОВ.предмет_назви(зр)
print("«%s»: ДО %s → ПІСЛЯ %s" % (зр, д, п))
print("ВПАЛО %d" % (len(різн_сл) + (0 if (д is None and п and п[0] == "низ") else 1)))
