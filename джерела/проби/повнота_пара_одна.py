# -*- coding: utf-8 -*-
"""Пара ремонту: ід, перейменування, нічия й відсутність входу в усіх споживачів."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import вердикт_моделі as В
import повнота_образу as П

старі = [dict(ід="о1", речі=["a", "b", "c"], день="перший", опори=[dict(правило="K-ACC-01")]),
         dict(ід="о2", речі=["a", "b"], день="другий", опори=[dict(правило="K-SIL-03")])]
ном = {і: (к, "00") for к, і in enumerate("abcd", 1)}
номерами = lambda о: dict(о, речі=["#%d·%s" % ном[і] for і in о["речі"]])
сцени = [("ід важливіший за склад", [dict(ід="о1", речі=["a", "b"])], "о1"),
         ("перейменування і нічия", [dict(ід="новий", речі=["a", "b"])], "о2"),
         ("повна заміна зі збереженим ід", [dict(ід="о2", речі=["d"])], "о2"),
         ("нема підстав для пари", [dict(ід="новий", речі=["d"])], None),
         ("порожні ід не є адресою", [dict(речі=[])], None)]
вад = 0
for назва, нові, очік in сцени:
    поп = dict(образи=старі)
    злите, _ = П.злити_з_неторканими(dict(образи=нові), поп)
    пара = next((о.get("ід") for о in злите["образи"] if о.get("речі") == нові[0]["речі"]), None)
    утр = В.утрачені_опори(нові, поп)[0]
    опора = next((о["образ"] for о in утр), None)
    очік_злиття = очік or нові[0].get("ід")
    ок = пара == очік_злиття and опора == очік
    вад += not ок
    print(назва, "· злиття:", пара, "· опори:", опора, "· очікувано:", очік, "·", ок)
поп = dict(образи=[номерами(о) for о in старі])
дні = П.дні_до_ремонту([["a", "b"]], поп, ном)
після, повернуто = П.дотримати_склад([["a", "b"]], поп, ном, {"c": dict(слот="сумка")})
ок = дні == ["другий"] and після == [["a", "b"]] and not повернуто
вад += not ок
print("нічия без ід · день:", дні, "· склад:", після, "·", ок)
print("вад:", вад)
sys.exit(bool(вад))
