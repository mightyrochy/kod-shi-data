# -*- coding: utf-8 -*-
"""Рядок 205: значення, які код кладе ПІСЛЯ «=» у рядки діагнозу прогону, — прозою чи кодами.

Живий виклик мосту `запити` на стендовому вході, без моделі: `pool · cuts=` (ключі
`відсічено.лічба` — `пакет_моделі._жорстке_відсічення`, `траурний_регістр`, жорстке «ні»),
`control · … · scenario_shifted=` (`міст_рука2._зіпсувати_сценарій`) і `поломка.що_змінено`
(`міст_рука2._що_змінено`). Кирилиця ПОЗА лапками «…» — фраза коду; у лапках — цитата
жінки чи тексту випадку, і вона лишається законно.
Запуск із теки `джерела`: `python3 проби/ч9_значення_діагнозу.py`."""
import json, os, re, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ)
os.chdir(ТУТ)
КИР = re.compile(r"[а-яіїєґА-ЯІЇЄҐ]")
ЦИТАТА = re.compile(r"«[^»]*»")
import bridge as B
вх = json.load(open("стенд_вх.json"))
вх["сценарій"] = {"нагода": "робота", "місце": "офіс", "година": 9, "темп_c": 18.0,
                  "опади": "ні", "рядок": "робочий день · офіс · 09:00 · 18 °C"}
for сід in (3, 4):
    вх["сід"] = сід
    r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    if r.get("помилка"):
        print("сід %d: міст відмовив — %s" % (сід, r["помилка"])); continue
    знач = [("pool · cuts", "%s=%d" % (к, v))
            for к, v in sorted(((r.get("відсічено") or {}).get("лічба") or {}).items())]
    знач += [("control · scenario_shifted", ч)
             for ч in str(r.get("псування_сценарію") or "").split("; ") if ч]
    що = str((r.get("поломка") or {}).get("що_змінено") or "")
    знач += [("control · what_changed", що)] if що else []
    проза = [п for п in знач if КИР.search(ЦИТАТА.sub("", п[1]))]
    print("\nсід %d · поломка руки 2: %s" % (сід, ",".join(r.get("поломки_руки_2") or []) or "—"))
    for де, з in знач:
        print("   %-26s %s%s" % (де, з[:78], "   ← ПРОЗА КОДУ" if (де, з) in проза else ""))
    print("   значень %d · прозою коду %d" % (len(знач), len(проза)))
