# -*- coding: utf-8 -*-
"""П-17 · реєстри: чи ПРОВІДНИЙ реєстр каже щось ЖІНЦІ, а не лише логу.

Запуск із теки `джерела`: `python3 проби/p17_реєстри.py`. До 18.09 тринадцять
K-REG-10…22 доходили лише до легенди пакета й до сліду — «лог бачить, людина ні».
Міряється: скільки дають ВЛАСНУ знахідку з регістром і `сила_нп`, коли реєстр
веде, і чи їде в ній смуга формальності, якої доти не було ніде у виході."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import реєстри as РЕ, реєстр_правил as РП

свої, німі = [], []
for ключ, д in РЕ.РЕЄСТРИ.items():
    # ВЛАСНІ маркери, а не перші три: «кашеміровий джемпер» тихої розкоші стоїть
    # і в класиці, і образ із таких слів домінанти не дає ЗА ПОБУДОВОЮ — це
    # властивість словника, не дефект емітента.
    чужі = {м for к2, д2 in РЕ.РЕЄСТРИ.items() if к2 != ключ
            for м in list(д2["маркери"]) + list(д2["слабкі"])}
    власні = [м for м in д["маркери"] if м not in чужі][:3] or list(д["маркери"][:3])
    речі = [dict(id="р%d" % i, назва=м, слот=с)
            for i, (м, с) in enumerate(zip(власні, ("верх", "низ", "взуття")))]
    зн, о = РЕ.перевірити(речі, РП._зн)
    мої = [з for з in зн if з["правило"] == д["ід"]]
    if not мої:
        німі.append((д["ід"], о.get("домінанта")))
        continue
    з = мої[0]
    lo, hi = д["смуга"]
    смуга_в_тексті = ("%d–%d" % (lo, hi)) in з["суть"]
    свої.append((д["ід"], з["регістр"], з["сила_нп"], смуга_в_тексті))
    print("%s %-14s регістр=%-8s сила_нп=%.2f смуга_в_рядку=%s  %s"
          % (д["ід"], ключ, з["регістр"], з["сила_нп"], смуга_в_тексті, з["суть"][:58]))

for ід, дом in німі:
    print("%s НІМИЙ: домінанти нема (%s) — знахідки законно нема" % (ід, дом))
print("\nсвоя знахідка: %d з %d · усі «репліка»: %s · смуга доїхала: %d"
      % (len(свої), len(РЕ.РЕЄСТРИ), all(р == "репліка" for _, р, _, _ in свої),
         sum(1 for *_, с in свої if с)))
assert len(свої) == len(РЕ.РЕЄСТРИ), "мовчать: %s" % німі
assert all(с for *_, с in свої), "смуга формальності не доїхала в рядок людині"
assert all(нп > 0 for _, _, нп, _ in свої), "сила_нп нульова — вимір не доїхав"
