# -*- coding: utf-8 -*-
"""ПРОБА МШ-1 (рядок 311): сторож П-3 і ЕХО мовного шару. Фікстура — ЖИВИЙ прогін стенда
28.09.2026 (ZHYVA=sonnet, сід 3): сім текстів картки рук 1 і 2, вхід у шар (внутрішня мова,
англійська проза «Чому цей образ» і «Як це носити») і відповідь шару (українська).
ДВА ВИПАДКИ на кожен текст: шар ВІДПОВІВ (вихід із фікстури) і шар ВЕРНУВ ВХІД (ехо —
збій виклику, не-JSON, повтор без змін). ДРУКУЄ, скільки з них знімає сторож ДО правки
(виняток «слово стояло у вході» рахувався завжди) і ПІСЛЯ (`своїВходуП`: вхід сам чужою
мовою винятку не дає). ЗАПУСК (тека `джерела`): python3 проби/мш1_ехо_шару.py"""
import io, json, os, re, subprocess, sys

ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
КОД = io.open(os.path.join(ТУТ, "показ.html"), encoding="utf-8").read()
ШМАТКИ = [re.search(р, КОД, re.S).group(0) for р in (
    r"const ЧАСТКА_ЧУЖОЇ_П = [\d.]+;",
    r"function словаП\(т\)\{.*?\n\}",
    r"function латинськеСловоП\(с\)\{.*?\n\}",
    r"function чужоюМовоюП\(т, свої\)\{.*?\n\}",
    r"function своїВходуП\(вхід\)\{.*?\n\}")]
ФІКС = json.load(io.open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                      "мш1_фікстура.json"), encoding="utf-8"))
ЖС = "\n".join(ШМАТКИ) + """
const стара = вхід => new Set(словаП(вхід).map(с => с.toLowerCase()));
const вих = [];
for (const ф of JSON.parse(process.argv[1]))
  for (const [випадок, т] of [['шар переклав', ф.вихід], ['ехо: шар вернув вхід', ф.вхід]])
    вих.push([ф.рука, ф.ключ, випадок,
              чужоюМовоюП(т, стара(ф.вхід)), чужоюМовоюП(т, своїВходуП(ф.вхід))]);
console.log(JSON.stringify(вих));
"""
п = subprocess.run(["node", "-e", ЖС, json.dumps(ФІКС, ensure_ascii=False)],
                   capture_output=True, text=True, encoding="utf-8")
if п.returncode:
    print("node впав:", (п.stderr or "")[-300:]); sys.exit(1)
РЯДКИ = json.loads(п.stdout)
for випадок in ("шар переклав", "ехо: шар вернув вхід"):
    свої = [р for р in РЯДКИ if р[2] == випадок]
    print("%-24s текстів %d · ДО сторож знімає %d · ПІСЛЯ %d"
          % (випадок, len(свої), sum(р[3] for р in свої), sum(р[4] for р in свої)))
print("ФАКТ: ехо шару ДО правки невидиме для сторожа (вхід сам англійський — усі слова "
      "відповіді «свої»); ПІСЛЯ — знімається, а справжній переклад не чіпається")
