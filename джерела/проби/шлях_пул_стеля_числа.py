"""Розбір 3/8: скільки речей у пулі — три різні числа на один пул.

`міст_пакет._пакет_у_бюджет` клало в `стеля.K` те, що ЗАПИТАНО в семплера, і тим
самим числом писало рядок «зрізано … до N речей». Скільки семплер ВІДДАВ,
рахувалось лише в гілці, де бюджет не витримано (`стеля.K_віддано`). Проба друкує
з прогону власника 25.09 (розклад 4123) те, що стоїть у файлі, і поруч —
`стеля`, яку на ТИХ САМИХ числах дає теперішній `міст_пакет.стеля_зрізу`.
Прогін: cd джерела && python3 проби/шлях_пул_стеля_числа.py
"""
import json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import міст_пакет as МП
ФАЙЛ = os.path.join(os.path.dirname(ТУТ), "аудит", "тести", "власник_2026-09-25",
                    "verdykty-0phxvk-2026-09-25-2012.json")
for пр in json.load(open(ФАЙЛ, encoding="utf-8"))["прогони"]:
    сп = пр["спільне"]
    руки = [в for в in пр["вердикти"] if str(в.get("рука")) in ("1", "2")]
    викл = ((руки[0].get("етапи") or {}).get("виклики") or []) if руки else []
    запит = ((викл[0].get("запит") or {}) if викл else {})
    текст = запит.get("текст") or ""
    if not текст.startswith("{"):
        continue
    пул = json.loads(текст).get("пул") or {}
    ном = [r.get("н") for с in пул for r in пул[с]]
    ет = (сп.get("етапи") or {}).get("прогін") or {}
    стеля = ет.get("стеля") or {}
    print("прогін розклад %s, колонка «пул» показу: %s" % (сп.get("розклад"), сп.get("пул")))
    print("  У ФАЙЛІ: стеля.K %s | позицій у ПАКЕТ_V1 %d | унікальних номерів %d | "
          "пул_речей %s | символів %d при бюджеті %s"
          % (стеля.get("K"), len(ном), len(set(ном)), ет.get("пул_речей"), len(текст),
             стеля.get("бюджет")))
    print("  поля стелі у файлі: %s" % ", ".join(sorted(стеля)))
    print("  рядок, який читає власник: %s" % str(стеля.get("чому"))[:120])
    # ПІСЛЯ ПРАВКИ: та сама стеля з тих самих чисел, теперішнім побудовником
    _сп = {"кандидати": {с: [{"id": r.get("н")} for r in рч] for с, рч in пул.items()},
           "текст": текст}
    нова = МП.стеля_зрізу(_сп, 228942, стеля.get("K") or 0, стеля.get("бюджет") or 120000)
    print("  ЗАРАЗ:   %s" % json.dumps({к: v for к, v in нова.items() if к != "чому"},
                                       ensure_ascii=False))
    print("  рядок ЗАРАЗ: %s" % нова["чому"][:150])
