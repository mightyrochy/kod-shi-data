# -*- coding: utf-8 -*-
"""Розбір 3/8: скільки речей у пулі — три різні числа на один пул.

`міст_пакет._пакет_у_бюджет` кладе в `стеля.K` те, що ЗАПИТАНО в семплера, і тим
самим числом пише рядок «зрізано … до N речей». Скільки семплер ВІДДАВ, рахується
лише в гілці, де бюджет не витримано (`стеля.K_віддано`), — у звичайній гілці
розбіжність не пишеться. Проба друкує з прогону власника 25.09 (розклад 4123)
запитане число, позиції пулу в ПАКЕТ_V1, унікальні номери речей і `пул_речей`.
Прогін: python3 проби/шлях_пул_стеля_числа.py
"""
import json, os
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ФАЙЛ = os.path.join(os.path.dirname(ТУТ), "аудит", "тести", "власник_2026-09-25",
                    "verdykty-0phxvk-2026-09-25-2012.json")
д = json.load(open(ФАЙЛ, encoding="utf-8"))
for пр in д["прогони"]:
    сп = пр["спільне"]
    руки = [в for в in пр["вердикти"] if str(в.get("рука")) in ("1", "2")]
    викл = ((руки[0].get("етапи") or {}).get("виклики") or []) if руки else []
    текст = ((викл[0].get("запит") or {}) if викл else {}).get("текст") or ""
    if not текст.startswith("{"):
        continue
    пул = json.loads(текст).get("пул") or {}
    ном = [r.get("н") for с in пул for r in пул[с]]
    ет = (сп.get("етапи") or {}).get("прогін") or {}
    стеля = ет.get("стеля") or {}
    print("прогін розклад %s, колонка «пул» показу: %s" % (сп.get("розклад"), сп.get("пул")))
    print("  стеля.K (запитано в семплера):      %s" % стеля.get("K"))
    print("  позицій у ПАКЕТ_V1.пул:             %d  (слотів %d)" % (len(ном), len(пул)))
    print("  унікальних номерів речей:           %d" % len(set(ном)))
    print("  етапи.прогін.пул_речей:             %s" % ет.get("пул_речей"))
    print("  стеля.K_віддано записано:           %s" % ("так" if "K_віддано" in стеля else "НІ"))
    print("  рядок, який читає власник: %s" % str(стеля.get("чому"))[:150])
    for с, рч in sorted(пул.items(), key=lambda кв: -len(кв[1]))[:4]:
        print("    слот %-12s %3d речей" % (с, len(рч)))
