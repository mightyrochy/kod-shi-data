# Рядок 9 дошки: оголошений хід ітерації 2 мусить пережити виклик 3 (ВИБІР_V1).
# Оголосити його можна ДВОМА способами, і код рахує обидва однаково (×0.6):
#   а) поле `свідомо` образу;  б) `виконано: {дія: відхилено, чому: …}` над знахідкою.
# ДО правки вердикт ніс у `образ.свідомі` лише (а) — (б) лишався самою міткою
# `знахідка.свідомий`, а `вибір_з_json` читає рівно `образ.свідомі`, тож (б) гинув:
# у виклику 3 знахідка поверталась до повної сили й `свідомі` виходив порожнім.
# Запуск: cd джерела && python3 проби/svidomi_vyklyk3.py
import sys, os, json, tempfile
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, feed as Ф

вх = json.load(open("стенд_вх.json", encoding="utf-8"))
d0 = dict(вх, каталог=Ф.каталог_на_диску("каталог_brief.xml"), варіантів=10, ремонт_варіантів=5,
          кеш_кольорів=os.path.join(tempfile.gettempdir(), "кеш_проби_свід3.json"))
міст = lambda **kw: json.loads(B.виклик("від_моделі", json.dumps(dict(d0, **kw), ensure_ascii=False)))
пул = json.loads(json.loads(B.виклик("запити", json.dumps(d0, ensure_ascii=False)))["руки"]["1"])["пул"]
н = lambda сл, i=0: пул[сл][i % len(пул[сл])]["н"]
склад = [н("сукня", 3), н("взуття"), н("сумка"), н("каблучка")]

образ = dict(ід="о1", підпис="вечірній тон", речі=склад)
вд1 = міст(текст_моделі=json.dumps(dict(версія="1", образи=[образ]), ensure_ascii=False))["вердикт"]
зн = [z for z in вд1["образи"][0]["знахідки"]
      if z.get("речі") and not z.get("блокує") and z.get("сила") != "питання" and z.get("сила_нп")][0]
print("іт.1 · знахідка %s над %s · сила %.2f" % (зн["правило"], зн["речі"], зн["сила_нп"]))

о2 = dict(образ, виконано=[dict(знахідка=зн["ід"], дія="відхилено", чому="це задум образу")],
          свідомо=[dict(річ=н("взуття"), чому="ці мюлі взяті навмисно")])
в2 = міст(ітерація=2, попередній_вердикт=вд1, текст_моделі=json.dumps(dict(версія="1", образи=[о2]), ensure_ascii=False))
зап = в2["вердикт"]["образи"][0]
сила = lambda де, пр: [(z.get("сила_нп"), bool(z.get("свідомий"))) for z in (де or []) if z.get("правило") == пр]
print("іт.2 · вердикт: %s %s · свідомі вердикта %s"
      % (зн["правило"], сила(зап.get("знахідки"), зн["правило"]), [с.get("річ") for с in (зап.get("свідомі") or [])]))
в3 = міст(ітерація=2, відповідь="ВИБІР_V1", вибір_над=в2["вибір_над"],
          текст_моделі=json.dumps(dict(версія="1", обрано="о1", чому="тримає задум"), ensure_ascii=False))
print("виклик 3 · розриви %s · %s %s · в3.свідомі %s"
      % ([р.get("річ") for р in (в3["вибір"].get("розриви") or [])], зн["правило"],
         сила(в3.get("знахідки"), зн["правило"]), [с.get("текст") for с in (в3.get("свідомі") or [])]))
