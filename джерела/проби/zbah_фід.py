# -*- coding: utf-8 -*-
"""Збагачення з фото в ЖИВОМУ ШЛЯХУ — що воно змінило в пулі руки 1, числами.

Той самий виклик, що продукт (`bridge.виклик("запити", стенд_вх)`), двічі: з
файлом опису і з вимкненим `feed.читати_збагачення`. Друкує колір/крій/тканину
рядка пулу до і після, стверджує, що рядок ПАКЕТА несе колір із фото, і звіряє
бал формальності проти `формальність.інтервал_типу` (поріг наряду 80 % не
взято — див. `feed.накласти_збагачення`); колір з фото — лише за згоди свідків
(`feed.колір_спір`, ПЕРЕДАЧА §5). Запуск: `python3 проби/zbah_фід.py`."""
import sys, pathlib, random, time
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ, bridge as B, feed as F, формальність as ФМ

def пул(без_фото=False):
    ст = F.читати_збагачення
    if без_фото: F.читати_збагачення = lambda тека=None: {}
    B._КЕШ_ПАКЕТА.clear(); B._ОСТАННІЙ_ПАКЕТ.clear()
    t = time.time()
    try: _, r, кат, _с = ПВ.стенд(гілка=0)
    finally: F.читати_збагачення = ст
    ряд = [x for рч in (r["кандидати"] or {}).values() for x in рч]
    зап = [кат.get(x["id"]) or {} for x in ряд]
    ч = lambda сп, п: 100.0 * sum(1 for x in сп if x.get(п)) / (len(ряд) or 1)
    return dict(ряд=ряд, кат=кат, речей=len(ряд), секунд=time.time() - t,
                крій=ч(ряд, "крій"), тканина=ч(ряд, "тканина"), colors=ч(зап, "colors"),
                фото=100.0 * sum(1 for x in зап if x.get("колір_джерело") == "фото") / (len(ряд) or 1))

до, після = пул(без_фото=True), пул()
print("пул руки 1 (стенд_вх, гілка 0):  БЕЗ фото →  З фото")
for п in ("речей", "секунд", "фото", "крій", "тканина", "colors"):
    print("   %-10s %8.1f → %8.1f" % (п, до[п], після[п]))
# ── ЗГОДА СВІДКІВ ЗАМІСТЬ «≥ 90 %» (18.09.2026, ПЕРЕДАЧА §5) ────────────────
# Наряд v1 вимагав колір із фото на ≥ 90 % пулу. Правило власника про
# під'єднання каже інше: колір з фото лише за згоди свідків (або коли крамниця
# кольору не назвала), а в спорі — слово крамниці й позначка `колір_спір`. Отже
# стеля — частка речей, чиї свідки згодні (на каталозі з жнивами v1 — 71 %
# придатних), і міряється не «скільки», а «чи кожна річ з описом або взяла
# колір із фото, або несе позначку спору»: мовчазних немає.
кат = після["кат"]
спори = [x for x in після["ряд"] if кат[x["id"]].get("колір_спір")]
мовчазні = [x for x in після["ряд"] if кат[x["id"]].get("збагачення")
            and кат[x["id"]].get("колір_джерело") != "фото" and not кат[x["id"]].get("колір_спір")]
print("ФАКТ · колір з фото %.1f %% (без файла %.1f); спорів із крамницею %d, мовчазних %d; "
      "час складання не виріс" % (після["фото"], до["фото"], len(спори), len(мовчазні)))
assert після["фото"] > до["фото"] and not мовчазні and після["секунд"] <= до["секунд"] * 1.2,     (після["фото"], до["фото"], len(мовчазні), після["секунд"], до["секунд"])
# РЯДОК ПАКЕТА, А НЕ ЛИШЕ ЗАПИС: до моделі їде саме він. `сім_я` не питається — у
# нейтралі (сірий, чорний, білий) тону нема, і порожнє поле там чесне.
кат = після["кат"]
зб = [x for x in після["ряд"] if кат[x["id"]].get("збагачення")]
без = [x for x in зб if x.get("колір") != кат[x["id"]]["колір_назва"] or not x.get("hex")]
print("ФАКТ · рядків пакета зі збагаченням %d; без слова або hex із фото: %d" % (len(зб), len(без)))
assert not без, без[:3]
речі = [c for c in кат.values() if c.get("формальність_фото") and ФМ.інтервал_типу(c["тип"])[0] is not None]
random.Random(17).shuffle(речі)
межі = [(ФМ.інтервал_типу(c["тип"])[:2], c["формальність_фото"]) for c in речі[:200]]
у = sum(1 for (л, х), ф in межі if л <= ф <= х)
поруч = sum(1 for (л, х), ф in межі if л - 1 <= ф <= х + 1)
print("ФАКТ · формальність із фото проти інтервалу типу (%d речей, сід 17): у інтервалі %.1f %%, "
      "у межах ±1 %.1f %% — поріг 80 %% не взято, бал лишається окремим `формальність_фото`"
      % (len(межі), 100.0*у/len(межі), 100.0*поруч/len(межі)))
assert not any(c.get("формальність") for c in кат.values()), "бал із фото підмінив ключ формальності"
