# -*- coding: utf-8 -*-
"""Збагачення з фото в ЖИВОМУ ШЛЯХУ — що змінилось у пулі руки 1, числами.

Той самий виклик, що продукт (`bridge.виклик("запити", стенд_вх)`), двічі: з
файлом опису і з вимкненим `feed.читати_збагачення`. Друкує частку кольору з
фото, крій і слово тканини в рядку пулу — до і після, — та звірку балу
формальності з фото проти `формальність.інтервал_типу` (поріг наряду 80 %).
Запуск із теки `джерела`: `python3 проби/zbah_фід.py`."""
import sys, pathlib, random, time
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ, bridge as B, feed as F, формальність as ФМ

def пул(без_фото=False):
    ст = F.читати_збагачення
    if без_фото: F.читати_збагачення = lambda тека=None: {}
    B._КЕШ_ПАКЕТА.clear(); B._ОСТАННІЙ_ПАКЕТ.clear()
    t = time.time()
    try: _, r, кат, _с = ПВ.стенд(гілка=0)
    finally: F.читати_збагачення = ст
    ряд = [x for рч in (r["кандидати"] or {}).values() for x in рч]
    зап = [кат.get(x["id"]) or {} for x in ряд]
    ч = lambda сп, п: 100.0 * sum(1 for x in сп if x.get(п)) / (len(сп) or 1)
    return dict(n=len(ряд), сек=time.time() - t, колір=ч(зап, "збагачення"),
                фото=100.0 * sum(1 for x in зап if x.get("колір_джерело") == "фото") / (len(ряд) or 1),
                крій=ч(ряд, "крій"), тканина=ч(ряд, "тканина"), площі=ч(зап, "colors")), кат

до, _ = пул(без_фото=True)
після, кат = пул()
print("пул руки 1 (стенд_вх, гілка 0):   БЕЗ фото → З фото")
for п, мітка in (("n", "речей"), ("сек", "секунд"), ("фото", "колір з фото %"),
                 ("крій", "крій у рядку пулу %"), ("тканина", "тканина в рядку пулу %"),
                 ("площі", "дві площі кольору (colors) %")):
    print("   %-30s %8.1f → %8.1f" % (мітка, до[п], після[п]))
print("ФАКТ · колір з фото %.1f %% (наряд: ≥ 90)" % після["фото"])
assert після["фото"] >= 90.0, після
assert після["сек"] <= до["сек"] * 1.2, (до["сек"], після["сек"])   # кеш: час не росте
речі = [c for c in кат.values() if c.get("формальність_фото") and ФМ.інтервал_типу(c.get("тип"))[0] is not None]
random.Random(17).shuffle(речі)
виб = речі[:200]
у, поруч = 0, 0
for c in виб:
    л, х, _ = ФМ.інтервал_типу(c["тип"]); ф = c["формальність_фото"]
    у += л <= ф <= х; поруч += (л - 1) <= ф <= (х + 1)
print("ФАКТ · формальність із фото проти інтервалу типу (200 речей, сід 17): "
      "у інтервалі %.1f %%, у межах ±1 %.1f %% — поріг 80 %% не взято, "
      "тому поле лишається окремим `формальність_фото`" % (100.0*у/len(виб), 100.0*поруч/len(виб)))
assert not any(c.get("формальність") for c in кат.values()), "бал із фото підмінив ключ формальності"
