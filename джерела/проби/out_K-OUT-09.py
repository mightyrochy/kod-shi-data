"""K-OUT-09 (однобортне хоче бути відкритим, двобортне — закритим).

ЧОМУ БУВ ЛИШЕ СЛІД: `outer.стан` писала `trace.запис` щоразу, коли обирала
дефолт, а знахідку віддає інша функція — `outer.стан_знахідки`, і батарея
аудиту кликала першу без другої. На живому шляху `перевірити` кличе обидві.
ЩО ПОКАЗУЄ ПРОБА: двобортне пальто без пояса → рядок «стан за замовчуванням:
застібнуто» стоїть у `вердикт.образи[0].знахідки`; перелік дозволених станів
їде ремонтом."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
вх["сценарій"].update(темп_c=5, опади="ні")
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
к = з["кандидати"]
# річ береться з КАТАЛОГУ пакета, не лише з пулу: ознака, під яку писане правило,
# трапляється в 92 із 618 речей слота, і `перевірити_від_моделі` законно судить річ поза
# кандидатами (вона лише лягає в `поза_кандидатами`) — тим самим шляхом, яким у
# продукт заходить річ, знайдена моделлю в повному каталозі.
ціль = next(c for c in кат.values() if c.get("слот") == "верхній_шар" and (c.get("бортність") == "двобортне" and not c.get("пояс")))
ід = [ціль["id"]] + [(к.get(сл) or [{}])[0].get("id") for сл in ("сукня", "взуття")
                     if (к.get(сл) or [])]
print("верхній шар:", ціль["назва"][:52])
print("ознака входу:", "бортність «%s», пояс %s" % (ціль.get("бортність"), ціль.get("пояс")))
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
р = next((z for z in (о.get("знахідки") or []) if z.get("правило") == "K-OUT-09"), None)
print("K-OUT-09 у вердикті:", "НЕМА" if not р else
      "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:62]))
print("речі рядка:", (р or {}).get("речі"), "· регістр", (р or {}).get("регістр"))
print("дозволені стани ремонтом:", str((р or {}).get("ремонт"))[:70])
