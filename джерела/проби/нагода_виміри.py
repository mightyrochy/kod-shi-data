# -*- coding: utf-8 -*-
"""НГ-1: паспорт нагоди v2 нічого не міняє в рішенні на нинішніх 18 ключах нагоди.

Зліпок = `формальність.сценарій` + ВИПАДОК пакета стилістці + `сценарій.день_кодами` на кожному
ключі нагоди (НГ-1: SHA до і після той самий; НГ-2 його свідомо змінив). Друге: перетин відповідності «поле паспорта → перелік кодів» із `мовний_шар`
мусить збігатися дослівно, крім `рух` (ядро знає 3 стани, подія 7: `РУХ_ЯДРА_У_ВИМІР`).
Запуск: cd джерела && python3 проби/нагода_виміри.py"""
import os, sys, json, hashlib
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import формальність as Ф, паспорт_нагоди as ПН, пакет_моделі as ПМ, сценарій as СЦ, мовний_шар as МШ

# НГ-2 змінив рішення свідомо (`проби/нагода_що_вирішує.py`); до НГ-2 — b5d0aec8…
НА_MAIN = "679e2cdcf02d69e962b612f874f53aac72418b3b9a415bd25947dae0ffe20e25"
рядки, вимірів = [], {}
for к in sorted(ПН.ключі_нагоди()):     # НГ-2: типове місце — пресет виду, не `НАГОДА_У_МІСЦЕ`
    сц = dict(нагода=к, місце=ПН.типове_місце(к), година=19, темп_c=12.0)
    п = ПН.паспорт_з_json("{}", сц, "")
    рядки.append(json.dumps([Ф.сценарій(нагода=к, місце=сц["місце"], година=19, темп_c=12.0),
                             ПМ.випадок_для_пакета(п, ПН.паспорт_рядком(п)), СЦ.день_кодами(сц)],
                            ensure_ascii=False, sort_keys=True, default=str))
    вимірів[к] = (п["виміри"], п["звідки"])
зліпок = hashlib.sha256("\n".join(рядки).encode("utf-8")).hexdigest()
знані = lambda з: sum(1 for в in з.values() if в != "unknown")
види = {в["kind"] for в, _ in вимірів.values()}
print("ключів нагоди: %d · зліпок рішення: %s · опора НГ-2: %s → %s"
      % (len(рядки), зліпок[:12], НА_MAIN[:12], "ТОЙ САМИЙ" if зліпок == НА_MAIN else "ЗМІНИВСЯ"))
print("видів різних: %d · вимірів оголошено: %d · заповнено на ключ: %d…%d"
      % (len(види), len(ПН.виміри_оголошені()),
         min(знані(з) for _, з in вимірів.values()), max(знані(з) for _, з in вимірів.values())))
for ім, пари, мій in (("прості", МШ._ПАСПОРТ_ПРОСТІ, dict((к, п) for _, п, к in ПН.ПОЛЕ_ВИМІРУ)),
                      ("числа", МШ._ПАСПОРТ_ЧИСЛА, dict((к, в) for в, к in ПН.ЧИСЛО_ВИМІРУ))):
    інакше = sorted((к, п, мій[к]) for к, п in пари if к in мій and мій[к] != п and к != "рух")
    print("мовний_шар %s: спільних полів %d · розійшлись %d %s"
          % (ім, sum(1 for к, _ in пари if к in мій), len(інакше), інакше or ""))
    assert not інакше, "два примірники відповідності розійшлись: %s" % (інакше,)
assert зліпок == НА_MAIN, "рішення на нинішніх ключах змінилось: %s ≠ %s" % (зліпок, НА_MAIN)
# 18 ключів → 17 видів: `весілля_денне` і `весілля_гість` — той самий вид, і різняться
# вимірами (частина доби проти ролі), а не назвою. Це і є §0.3 проєкту.
assert len(види) == 17, "18 ключів мусять дати 17 видів, дали %d" % len(види)
assert all(з["kind"] != "unknown" for _, з in вимірів.values()), "ключ нагоди без виду"
