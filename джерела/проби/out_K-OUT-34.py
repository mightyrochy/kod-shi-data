# -*- coding: utf-8 -*-
"""K-OUT-34 (ціна стану «накинуто» названа носійками, і вона не естетична).

ДО ПРАВКИ: `outer.команди_укладки` віддавала знахідку у відро `команди`, яке до
вердикту не доїжджало. Модель радила «накинути» (K-OUT-32), не чуючи ціни.
ПІСЛЯ: обидва рядки стоять у `вердикт.образи[0].знахідки` поруч — порада й ціна
приїжджають разом, а не порада без ціни."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
вх["сценарій"].update(темп_c=5, опади="ні")
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
к = з["кандидати"]
взяти = lambda сл, ум: next((кат[r["id"]] for r in (к.get(сл) or [])
                             if r["id"] in кат and ум(кат[r["id"]])), None)
# «накинуто» тримає лише конструйоване плече (K-OUT-33): пальто, тренч, плащ
пальто = взяти("верхній_шар", lambda c: c.get("тип_верхнього") == "пальто"
               and c.get("рукав") != "реглан")
ід = [r["id"] for r in (пальто, взяти("сукня", lambda c: True),
                        взяти("взуття", lambda c: True)) if r]
print("верхній шар:", пальто["назва"][:56], "· тип", пальто.get("тип_верхнього"))
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
зн = ((вм.get("вердикт") or {}).get("образи") or [{}])[0].get("знахідки") or []
for код in ("K-OUT-34", "K-OUT-32"):
    р = next((z for z in зн if z.get("правило") == код), None)
    print("%s у вердикті: %s" % (код, "НЕМА" if not р else
          "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:56])))
print("ціна стану рядком:", str(next((z.get("ремонт") for z in зн
                                      if z.get("правило") == "K-OUT-34"), None))[:90])
