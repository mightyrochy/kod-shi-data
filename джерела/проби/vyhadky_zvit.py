# -*- coding: utf-8 -*-
"""Вигадана цитата моделі ЗАПИСУЄТЬСЯ, а не гасне мовчки (слово власника 25.09.2026: «якщо модель щось
вигадує, це має бути записано в доповіді у вердиктах»). Друкує запис так, як його бачить власник у файлі
«Скопіювати всі вердикти». Із теки `джерела`: PYTHONPATH=. python3 проби/vyhadky_zvit.py"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); import паспорт_нагоди as ПН

СЛОВА = "люблю смужку, і взуття зручне"
ЦИТАТИ = {ПН.ключ_цитати("принти", "смужка"): "смужку не ношу",      # власна вигадка моделі
          ПН.ключ_цитати("типи", "куртка"): "не темного кольору"}    # приклад із самого промпта
РЯДОК = ('вигадка моделі · крок вето · поле %s · модель сказала: "%s", цитата "%s" · у її словах: нема '
         'опори · ймовірне джерело: %s · що зробив код: вето не тверде · чи вплинуло на образ: ні — '
         'з пулу нічого не знято, слово лишилось видимим на картці сценарію')

тв = ПН.вето_тверде(dict(слова=СЛОВА, цитати_слів=ЦИТАТИ,
                         вето=dict(принти=["смужка"], типи=["куртка"], тканини=[], кольори=[], зони=[])))
вигадки = тв.get("вигадки") or []
for в in вигадки:
    print(РЯДОК % (в["поле"], в["слово"], в["цитата"], в["джерело"]))
print("ФАКТ: вигадок записано %d · твердих меж лишилось: принти %s · типи %s"
      % (len(вигадки), тв["принти"], тв["типи"]))
# ДЖЕРЕЛО ВИЗНАЧАЄТЬСЯ ЗА ЦИТАТОЮ, А НЕ ЗА СЛОВОМ. Спершу перевірялось і слово — і «смужку не ношу»
# хибно діставало ярлик «приклад промпту», бо слово «смужка» в промпті стоїть цілком законно.
assert {в["джерело"] for в in вигадки} == {"приклад промпту", "невідомо"}, вигадки
assert len(вигадки) == 2 and not тв["принти"] and not тв["типи"]
# ЧЕСНА ЦИТАТА ЗАПИСУ НЕ ЛИШАЄ: вигадка — це те, чого в її словах нема, а не кожне вето.
чесне = ПН.вето_тверде(dict(слова="смужку не ношу", вето=dict(принти=["смужка"], типи=[], тканини=[],
    кольори=[], зони=[]), цитати_слів={ПН.ключ_цитати("принти", "смужка"): "смужку не ношу"}))
print("ФАКТ: при чесній цитаті — вигадок %d, тверді принти %s"
      % (len(чесне.get("вигадки") or []), чесне["принти"]))
assert not чесне.get("вигадки") and чесне["принти"] == ["смужка"]
