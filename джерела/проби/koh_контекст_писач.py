"""Друкує шлях фактів K-KOH-07 від відповіді моделі до сценарію й чекліста."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import мовний_шар as М, паспорт_нагоди as П, формальність as Ф, суд_образу as Суд
import схема_відповіді as С, сценарій as День, дріт_моделі as Д


if __name__ == "__main__":
    схема = С.форма_мовного_шару(визначення=False)["properties"]["update"]["properties"]
    for поле, ім, так, ні, ризик in (
            ("host_context", "господар", "Йду на ювілей свекрухи, вона господиня події",
             "Господаря події та ставок немає", "half_step_over"),
            ("creative_environment", "креативне", "Подія у творчому середовищі",
             "Середовище не творче", "half_step_under_plus_detail")):
        assert поле in схема
        досі = {}
        for код, слова, значення in (("unknown", "На побачення", None), ("yes", так, True),
                                     ("no", ні, False), (None, "Ще хочу сумку", False)):
            оновлення = {поле: {"value": код, "quote": слова}} if код else {}
            р = М.прийняти_розмову(json.dumps({"update": оновлення, "text": "Записала", "need": "none"}))
            п = М.паспорт_з_шару(р["внутрішня"], {}, паспорт_досі=досі, слова_ходу=[так, ні, слова])["паспорт"]
            н, _ = П.з_показу({}, п)
            assert н.get(ім) is значення, (поле, код, н)
            день = День.день_кодами(н)
            assert (поле in день) == (значення is not None)
            сц = Ф.сценарій(**{ім: н.get(ім)})
            assert сц["risk_posture"] == (ризик if значення is True else "neutral"), сц
            ч = Суд.чеклісти([], [], **{ім: н.get(ім)})
            пункт = next(п for п in ч["надлишок"] if п["вхід"] == ім)
            assert пункт["стан"] == ("без входу" if значення is None else "пройдено"), пункт
            if значення is None:
                assert пункт["бракує"][0]["fields"] == [ім]
            else:
                assert пункт["значення"] is значення
                assert М.паспорт_кодами(п)[поле] == ("yes" if значення else "no")
                assert п["цитати_полів"][ім] == (так if значення else ні)
                assert день[поле] is значення and Д.випадок({ім: значення})[поле] is значення
                assert поле not in Д.випадок({ім: значення}, день=день)
            досі = п
            print(поле, код or "пропущено", "→", н.get(ім), "→", сц["risk_posture"], "→", пункт["стан"])
