"""K-COMP-03 і K-COMP-05 — «БЕЗ ВХОДУ», і вхід названо числом:
`python3 проби/comp_K-COMP-03-05.py`.

Обидва емітенти повні (`колір_образу.сім_ї_образу` — ≤3 колірні сім'ї;
`колір_образу.відлуння` — правило відлуння, у корпусі K-COL-05 = K-COMP-05), і
обидва стоять ЗА ГЕЙТОМ ПЛОЩ: `review` виносить цю гілку лише коли КОЖНА річ
образу несе `джерело_площі`. Частка площі — це відношення до суми по ЦІЛОМУ
образу, тож над підмножиною вона хибна; сумка й прикраси країв не мають зовсім, і
покриття на живому шляху нульове.
ЧОМУ ЗАГЛУШКА 1/N ТУТ НЕ РЯТУЄ, А ШКОДИТЬ (вимір 08.09.2026, образ із шести
речей): заглушка ОДНОЧАСНО додала три хибні знахідки — дрібні сережки й брошка
перевалили `min_area`, бо 1/6 = 0.167, і K-COMP-03 порахував їх окремими
колірними сім'ями — і проковтнула справжню: два сироти-акценти на реальних площах
0.005 і 0.007, тобто рівно K-COMP-05. Помилка в ОБИДВА боки, не «трохи неточно».
ЩО ДРУКУЄ ПРОБА: утримання, яке виходить замість вердикту, і запис у реєстрі
обмежень із названою дією, що його зніме."""
import sys, pathlib, json
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import feed as Ф, bridge as B, status as СТ, colorspace as КС

вх = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml"); вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
барв = [c for c in кат if c.get("lab") and КС.lch(c["lab"])[1] > 30]
взяті, іди = set(), []
for сл in ("верх", "низ", "взуття", "сумка", "шарф"):
    c = next((c for c in барв if c.get("слот") == сл and c["id"] not in взяті), None)
    if c: взяті.add(c["id"]); іди.append(c["id"])
print("образ із %d барвистих речей (сімей свідомо понад ліміт)" % len(іди))
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=іди), ensure_ascii=False)))
о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
коди = [z["правило"] for z in (о.get("знахідки") or [])]
print("K-COMP-03 у вердикті:", "є" if "K-COMP-03" in коди else "НЕМА")
print("K-COL-05 (=K-COMP-05) у вердикті:", "є" if "K-COL-05" in коди else "НЕМА")
утр = [q for q in (вм.get("питання") or []) if "площ" in str(q.get("суть"))]
print("замість вердикту виходить утримання:", (утр[0]["суть"] if утр else "НЕМА"))
скільки = sum(1 for c in кат if c.get("джерело_площі"))
print("речей каталогу з ПОХОДЖЕННЯМ площі: %d із %d" % (скільки, len(кат)))
обм = next((з for з in СТ.ОБМЕЖЕННЯ if з["id"] == "виміряна_площа_речі"), None)
print("знімається:", (обм or {}).get("знімається", "НЕМА")[:92])
assert утр and обм and скільки == 0
