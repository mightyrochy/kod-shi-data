"""Рядки 6521, 6458, 6523: replay перших ходів ЖИВІ-1016-1 (Ж:16–50) і ЖИВІ-1016-2 (№1–7) тим самим кодом, без моделі.
1) Поля, чий уривок розійшовся з її словами на літери (її фрагмент — до 4 знаків від уривка): ДО — дослівна звірка
   знімала всі 7; ПІСЛЯ — `_тримається` з `її_фрагмент` (допуск 1–2 знаки), її фрагмент — уривком поля. Решта
   знятого (без уривка, «кафе» на «кава») — як доти.
2) Місяць свята: записані відповіді — `month` 0 з 5 (модель не дала); правка — промпт (R6), міряє живий прогін.
3) Ж:20 сід 5 `preciptation` — ключ поза схемою: що з ним робить шов і чи просить повтор (`повтор`, рядок 6523).
Запуск: cd джерела && python3 проби/перший_хід_уривок_6521.py"""
import json, re, subprocess, sys
sys.path.insert(0, "."); import мовний_шар as М
git = lambda *а: subprocess.run(["git", "-c", "core.quotepath=false", *а], capture_output=True, text=True).stdout
git("fetch", "-q", "origin", "claude/zhyvi-1016-1", "claude/zhyvi-1016-2")
ДОПУСК = М.ДОПУСК_ЛІТЕР
ДО = ПІСЛЯ = усього = 0
місяць, опади = [], None
for Г, взір in (("origin/claude/zhyvi-1016-1", r"живі_1016_1/(1[6-9]|[2-4]\d|50)_[^/]*/VIDPOVIDI/seed\d_01_мовний"),
                ("origin/claude/zhyvi-1016-2", r"живі_1016_2/0\d_[^/]*/VIDPOVIDI/seed\d_01_мовний")):
    for ф in sorted(ф for ф in git("ls-tree", "-r", "--name-only", Г, "../аудит/").split("\n") if re.search(взір, ф)):
        пр, від = git("show", "%s:%s" % (Г, ф)).split("── ВІДПОВІДЬ", 1)
        її, від = json.loads(пр.split("──\n", 1)[1])["her_new_message"], від.split("──", 1)[1]
        сц = ("Ж:" if "1016_1" in ф else "Ж-2 №") + ф.split("/")[-3][:2]
        р, виправлено = М.прийняти_розмову(від), []
        в, зняті = М._тримається(р["внутрішня"], [її], виправлено)
        М.ДОПУСК_ЛІТЕР = ((5, 4),)          # «через літери» — її фрагмент до 4 знаків від уривка
        цит = {к: ц for к, ц in (р["внутрішня"].get("quotes") or {}).items() if к in р["внутрішня"]}
        літерами = [к for к, ц in цит.items() if not М.цитата_тримає(ц, її) and М.її_фрагмент(ц, її)]
        М.ДОПУСК_ЛІТЕР = ДОПУСК
        ДО += len(літерами)
        ПІСЛЯ += sum(1 for к in літерами if any("field=%s " % к in x for x in зняті))
        усього += len(зняті)
        for x in виправлено:
            print("  %s %s" % (сц, x.split(" · ", 2)[2]))
        if re.search(r"(?i)новорічн|різдвян", її):
            місяць.append("%s %s" % (сц, в.get("month")))
        if сц == "Ж:20":
            опади = (р["внутрішня"].get("precipitation"), [x for x in р["не_взято"] if "preciptation" in x], р.get("повтор"))
print("полів, знятих через літери: ДО %d → ПІСЛЯ %d; знятих сторожем усього ПІСЛЯ %d" % (ДО, ПІСЛЯ, усього))
print("month у записаних відповідях свят:", місяць)
print("R6 будить month:", '"month"' in М.РОЗМОВА_ПРАВИЛА[6], "· R4 літери без кодів:", "Unicode escape" in М.РОЗМОВА_ПРАВИЛА[4])
print("Ж:20 опади:", опади)
