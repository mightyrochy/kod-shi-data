# -*- coding: utf-8 -*-
"""Рядок 168: чи лишається в пулі рук 1–2 річ, знімка якої браузер не покаже.
СЛОВО ВЛАСНИКА 24.09: «Прибрати skripka з образів рук». Крамниці в коді проби нема:
заборонені хости читаються з ДАНИХ виміру (`фід_фото.читати_показ`) — звідти, звідки їх
читає продукт, — тож проба ловитиме й наступну таку крамницю, не міняючись.
«ДО» — той самий прогін із вимкненим відсіченням (`_ПОЛЕ_БЕЗ_ПОКАЗУ` вказує на поле, якого
в записі нема), «ПІСЛЯ» — нинішній. Кеш пакета чиститься між прогонами: інакше другий
віддав би відповідь першого (спіймано на цій-таки пробі).
Запуск із `джерела`: PYTHONPATH=. python3 проби/bez_skripka_168.py"""
import collections, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, стенд_знімок as С, пакет_моделі as ПМ, міст_пакет as МП, фід_фото as ФФ
ЗАБОРОНА, ПОЛЕ = tuple(ФФ.читати_показ().get("хости") or ()), ПМ._ПОЛЕ_БЕЗ_ПОКАЗУ  # хости з ДАНИХ
лічба, речей = {м: collections.Counter() for м in ("ДО", "ПІСЛЯ")}, dict(ДО=0, ПІСЛЯ=0)
def прогін(сцена, режим):
    """Пул руки 1 цієї сцени; «ДО» — з вимкненим відсіченням «показати нема чого»."""
    ПМ._ПОЛЕ_БЕЗ_ПОКАЗУ = ПОЛЕ if режим == "ПІСЛЯ" else "_поля_нема_" + режим
    МП._КЕШ_ПАКЕТА.clear()
    вх = json.load(open("стенд_вх.json"))
    вх["сценарій"], вх["випадок"] = dict(С.СЦЕНАРІЇ[сцена]), сцена
    п = json.loads(json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["руки"]["1"])
    маг = п.get("магазини") or {}
    return {сл: [x for x in рч if маг.get(str(x.get("н")).split("·")[-1]) in ЗАБОРОНА]
            for сл, рч in (п.get("пул") or {}).items()}, sum(len(v) for v in (п.get("пул") or {}).values())
for сцена in С.СЦЕНАРІЇ:
    рядок = []
    for режим in ("ДО", "ПІСЛЯ"):
        за_сл, усього = прогін(сцена, режим)
        речей[режим] += усього
        for сл, рч in за_сл.items():
            лічба[режим][сл] += len(рч)
        рядок.append(sum(len(v) for v in за_сл.values()))
    print("  %-22s ДО %3d → ПІСЛЯ %3d" % (сцена, рядок[0], рядок[1]))
ПМ._ПОЛЕ_БЕЗ_ПОКАЗУ = ПОЛЕ
print("сцен %d · хостів заборони %d (%s) · речей у пулах: ДО %d, ПІСЛЯ %d\n"
      "РЕЧЕЙ ІЗ ЗАБОРОНЕНОГО ХОСТА В ПУЛІ: ДО %d · ПІСЛЯ %d"
      % (len(С.СЦЕНАРІЇ), len(ЗАБОРОНА), ", ".join(ЗАБОРОНА) or "—", речей["ДО"], речей["ПІСЛЯ"],
         sum(лічба["ДО"].values()), sum(лічба["ПІСЛЯ"].values())))
for сл in sorted(лічба["ДО"] | лічба["ПІСЛЯ"]):
    print("  %-16s ДО %3d → ПІСЛЯ %3d" % (сл, лічба["ДО"][сл], лічба["ПІСЛЯ"][сл]))
