# -*- coding: utf-8 -*-
"""Рядок 51: чи показує картка ОБРАНИЙ КАДР збагачення, чи перше фото фіду.

`жнива_v2` обирають кадр, де річ видно цілком, і кладуть його URL у `запис.фото`
(`жнива_v2.py:1195`). Картка ж бере `фото[0]` оффера (`bridge.py:3225`) — на
чоботях LeBERDES це підошва. Проба міряє на ЖИВОМУ каталозі три числа: скільки
речей мають кадр ≠ перше фото, скільки з них картка (`bridge.показ`) показує
кадром, і скільки карток усього каталогу змінили фото проти `фото[0]`.
Запуск: `python3 проби/foto_kadr_51.py`."""
import sys, json, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B, feed as F

зб = F.читати_збагачення()
шлях = F.каталог_на_диску()
оф = F.читати_yml(шлях)[0]
перше = {o["id"]: [x for x in (o.get("фото") or []) if x] for o in оф}
кадр = {}
for ід, ф in перше.items():
    з = зб.get(ід)
    к = з.get("фото") if isinstance(з, dict) else None
    if к and к in ф:
        кадр[ід] = к
цілі = [ід for ід, к in кадр.items() if к != перше[ід][0]]
картки = json.loads(B.показ(dict(каталог=шлях, речі=list(перше))))
показано = {к["id"]: к.get("фото") for к in картки}
взяли = [ід for ід in цілі if показано.get(ід) == кадр[ід]]
змінили = [ід for ід, ф in перше.items() if ф and показано.get(ід) != ф[0]]
без_зб = [ід for ід in змінили if ід not in кадр]
print("каталог: %s · оферів %d · збагачення з кадром серед фото речі: %d"
      % (pathlib.Path(шлях).name, len(перше), len(кадр)))
print("кадр ≠ перше фото: %d речей" % len(цілі))
print("картка показує ОБРАНИЙ КАДР: %d із %d" % (len(взяли), len(цілі)))
print("фото картки змінилось проти фото[0] фіду: %d речей (без збагачення: %d)"
      % (len(змінили), len(без_зб)))
print("приклади:", ", ".join("%s → %d-те фото" % (ід, перше[ід].index(кадр[ід]) + 1)
                             for ід in цілі[:3]) or "—")
