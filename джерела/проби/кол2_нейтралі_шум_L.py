# -*- coding: utf-8 -*-
"""КОЛ-2 (рядок 591): шум ΔL* між двома кадрами ОДНІЄЇ нейтралі — похибка входу другої умови K-COL-06.

Вхід — `каталог_кадри.json.gz`, пари кадрів одного кольорового варіанта (корінь імені — як у
`кол1_нейтралі_шум.py`), кадри-свідки (клас не з `НЕ_СВІДКИ`), обидва — нейтралі. Пара береться лише тоді,
коли кожен кадр УЗГОДЖЕНИЙ зі словом другого (`фід_кадр_колір.узгоджений` — та сама умова, за якою рішення
про колір приймає кадр як колір речі): кадри чужої речі (білий проти чорного) — не шум виміру, їх ловить
R-FEED-01. Обмеження ΔL* < кроку НЕМА: міряється саме ΔL*. Правдива ΔL* = 0, тож хвіст — похибка входу.
Запуск із теки `джерела`: `python3 проби/кол2_нейтралі_шум_L.py`."""
import sys, pathlib, gzip, json, itertools, re
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import колір_образу as К, verify as V
from реєстр_правил import C
from фід_кадр_колір import НЕ_СВІДКИ, узгоджений
корінь_файлу = lambda ф: re.sub(r"[_-]?\d+$", "", re.sub(r"_[0-9a-f]{8}-[0-9a-f-]{20,}$", "",
                                                            ф.rsplit("/", 1)[-1].rsplit(".", 1)[0]))
згода = lambda a, b: узгоджений(a["слово"], tuple(b["lab"]), V.сім_я_слова(b["слово"]))
усі, шум = [], []
for кадри in json.load(gzip.open(pathlib.Path(__file__).resolve().parent.parent / "каталог_кадри.json.gz",
                                 "rt", encoding="utf-8"))["записи"].values():
    гр = {}
    for к in кадри:
        if к.get("lab") and к.get("клас") not in НЕ_СВІДКИ and к.get("слово") in V.ЛЕКСИКОН:
            гр.setdefault(корінь_файлу(к["файл"]), []).append(к)
    for a, b in (п for g in гр.values() for п in itertools.combinations(g, 2)):
        if К.нейтраль(tuple(a["lab"])) and К.нейтраль(tuple(b["lab"])):
            усі.append(abs(a["lab"][0] - b["lab"][0]))
            if згода(a, b) and згода(b, a):
                шум.append(усі[-1])
q = lambda x, p: sorted(x)[min(len(x) - 1, int(p * len(x)))]
for ім, x in (("усі пари", усі), ("узгоджені (шум входу)", шум)):
    print("ФАКТ · %s: %d · |ΔL*| медіана %.1f, p90 %.1f, p95 %.1f, p99 %.1f, макс %.1f · ≥ step_min (%.0f): %.1f %%"
          % (ім, len(x), q(x, .5), q(x, .9), q(x, .95), q(x, .99), max(x), C["step_min"],
             100.0 * sum(1 for v in x if v >= C["step_min"]) / len(x)))
ш = C.get("ΔL_шум_нейтралей")
if ш is not None:
    print("ФАКТ · ΔL_шум_нейтралей %.1f · «одна світлота» на виміряних hex — лише при ΔL* < %.1f (%s)"
          % (ш, C["step_min"] - ш, "недосяжно: шум ≥ кроку" if ш >= C["step_min"] else "смуга до кроку — без входу"))
