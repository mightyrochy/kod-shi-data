# -*- coding: utf-8 -*-
"""КОЛ-2 (рядок 591): шум ΔL* між двома кадрами ОДНІЄЇ нейтралі — похибка входу другої умови K-COL-06.

Вхід — `каталог_кадри.json.gz`, пари кадрів одного кольорового варіанта (той самий корінь імені, що в
`кол1_нейтралі_шум.py`), кадри-свідки (клас не з `НЕ_СВІДКИ`), обидва кадри — нейтралі
(`колір_образу.нейтраль`). Обмеження ΔL* < кроку тут НЕМА: міряється саме ΔL*. Правдива ΔL* = 0, тож
кожна пара з ΔL* ≥ `step_min − шум` у смузі «одна світлота?» — суд над шумом. Друкує квантилі |ΔL*| і
частку пар, яку виміряна ΔL* вивела б за крок (≥ step_min).
Запуск із теки `джерела`: `python3 проби/кол2_нейтралі_шум_L.py`."""
import sys, pathlib, gzip, json, itertools, re
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import колір_образу as К
from реєстр_правил import C
from фід_кадр_колір import НЕ_СВІДКИ
корінь_файлу = lambda ф: re.sub(r"[_-]?\d+$", "", re.sub(r"_[0-9a-f]{8}-[0-9a-f-]{20,}$", "",
                                                            ф.rsplit("/", 1)[-1].rsplit(".", 1)[0]))
шум = []
for кадри in json.load(gzip.open(pathlib.Path(__file__).resolve().parent.parent / "каталог_кадри.json.gz",
                                 "rt", encoding="utf-8"))["записи"].values():
    гр = {}
    for к in кадри:
        if к.get("lab") and к.get("клас") not in НЕ_СВІДКИ:
            гр.setdefault(корінь_файлу(к["файл"]), []).append(tuple(к["lab"]))
    for g in гр.values():
        шум += [abs(a[0] - b[0]) for a, b in itertools.combinations(g, 2) if К.нейтраль(a) and К.нейтраль(b)]
шум.sort()
q = lambda p: шум[min(len(шум) - 1, int(p * len(шум)))]
над = lambda т: 100.0 * sum(1 for x in шум if x >= т) / len(шум)
print("ФАКТ · пар кадрів однієї нейтралі: %d · |ΔL*| медіана %.1f, p90 %.1f, p95 %.1f, p99 %.1f, макс %.1f"
      % (len(шум), q(.5), q(.9), q(.95), q(.99), шум[-1]))
print("ФАКТ · пар однієї нейтралі з виміряною ΔL* ≥ step_min (%.0f): %.2f %%" % (C["step_min"], над(C["step_min"])))
for т in (2, 4, 6, 8):
    print("ФАКТ · |ΔL*| ≥ %d: %.2f %%" % (т, над(т)))
if "ΔL_шум_нейтралей" in C:
    print("ФАКТ · ΔL_шум_нейтралей = %.1f · смуга «без входу» %.1f…%.0f" % (C["ΔL_шум_нейтралей"],
          C["step_min"] - C["ΔL_шум_нейтралей"], C["step_min"]))
