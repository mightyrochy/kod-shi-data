"""Походження на зібраних входах: картка, плитки, пакет і колір через кеш фіду."""
import sys, json
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import паспорт_поля as П, картка_запиту as К, мовний_шар as М, паспорт_нагоди as Н
import пакет_моделі as Б, дріт_моделі as Д, руки_без_коду as Р, оцінка_образу as О
import розбір_відповідей as В, сценарій as С, selection_policy as ПВ

def main():
    """Перевірити перенесення виду до моделі та збереження сильнішого факту в картці."""
    п = {}
    К.записати(п, "місце", "парк", П.ЇЇ, "парк")
    К.записати(п, "нагода", "побачення", П.ЇЇ, "йду на зустріч")
    К.записати(п, "темп_c", 18, П.ТИПОВЕ)
    вих = М.плитки_кодами({}, п)
    assert вих["sources"]["place"] == {"kind": "her", "quote": "парк"}, вих
    assert вих["sources"]["occasion"]["kind"] == "reading" and "temperature_c" not in вих
    К.записати(п, "місце", "офіс", П.ВИВЕДЕНЕ)
    assert п["місце"] == "парк"
    assert Р.головний_колір({"база": "синій", "база_за_замовчуванням": True})["chosen_by"] == "code"
    сц = {"макіяж": {"губи": "#bb3344"}, "типові_поля": []}
    промпт = json.loads(Н.промпт_паспорта(сц, ""))
    assert промпт["обрано_джерела"]["макіяж"]["kind"] == "derived", промпт
    assert Н.макіяж_канон(Н.макіяж_канон(сц["макіяж"]))["рівень_джерело"] == "derived"
    нагода = Н.з_показу({}, {})[0]
    assert С.день_кодами(нагода)["season_source"]["kind"] == "default"
    assert О._питання_дроту("Чи пасує?")["lang_source"]["kind"] == "default"
    assert ПВ.на_дріт(ПВ.опис())["goals"]["intent_source"]["kind"] == "derived"
    пакет = Б.випадок_для_пакета(п, "")
    assert Д.випадок(пакет)["sources"]["place"]["kind"] == "her"
    річ = В.речі_з_тексту("Синя сукня, прямий крій, міді, синій #334488, бавовна")["речі"][0]
    assert річ["джерело_кольору"] == "модель" and річ["колір_тип"] != "вимір", річ
    дріт = Д.річ(Б.річ_пулу(річ, {}))
    assert дріт["color_not_measured"]["source"] == "model_hex", дріт
    assert дріт["branch_source"]["kind"] == "default", дріт
    assert дріт["confidence_source"]["kind"] == "default", дріт
    print("Вид до дроту: її слово, тлумачення, типове, виведене; колір моделі через кеш не стає фото-виміром.")

if __name__ == "__main__":
    main()
