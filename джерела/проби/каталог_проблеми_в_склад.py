# -*- coding: utf-8 -*-
# Реєстр проблем бази одягу, напрям В, клас «тканина й склад». ФАКТ на одязі (верх, низ,
# сукня, верхній шар): (1) скільки речей мають `param склад`; (2) склад без жодного відсотка,
# із сумою відсотків не 100, із чужим текстом сторінки (склеєні слова, «Дивіться також»,
# «Правила»); (3) похідне поле жниварки `матеріал_родина` проти слів складу й назви: «вовна»
# без жодного вовняного волокна, «шовк» без шовку. Слова тут читає ПРОБА, не код продукту.
import os, re, sys, collections as C
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed
КАТ = sys.argv[1] if len(sys.argv) > 1 else feed.каталог_на_диску()
оф = feed.читати_yml(КАТ)[0]
# вхід виміру — першим рядком (наряд 0.4, рядок 8101): числа двох прогонів порівнюються лише на тому самому архіві
_п = feed.походження_каталогу(КАТ)
print("вхід: %s ← %s · sha256 %s" % (os.path.basename(КАТ), _п["архів"] and os.path.basename(_п["архів"]) or "(без архіву)",
                                      (_п["sha256_архіву"] or "—")[:16]))
одяг = [o for o in оф if feed.слот(o) in ("верх", "низ", "сукня", "верхній_шар")]
П = lambda o: o.get("параметри") or {}
склад = [(o, П(o).get("склад") or "") for o in одяг]
є = [(o, с) for o, с in склад if с.strip()]
відс = lambda с: [int(x) for x in re.findall(r"(\d{1,3})\s*%", с)]
сума = lambda в: any(sum(в[:i]) == 100 for i in range(1, len(в) + 1))
ЧУЖЕ = re.compile(r"[а-яіїє][А-ЯІЇЄ][а-яіїє]{3,}|(?i:дивіться також|правила|таблиц|доставк|відгук|розмір)")
print("одягу %d · зі складом %d (%.0f %%)" % (len(одяг), len(є), 100 * len(є) / len(одяг)))
print("склад без %%: %d · сума відсотків ≠ 100: %d · чужий текст сторінки: %d"
      % (sum(1 for _, с in є if not відс(с)), sum(1 for _, с in є if відс(с) and not сума(відс(с))),
         sum(1 for _, с in є if ЧУЖЕ.search(с))))
print("  приклади чужого:", [с[:60] for _, с in є if ЧУЖЕ.search(с)][:3])
ВОВНА = re.compile(r"вовн|wool|шерст|кашемір|cashmere|альпак|мохер|merino|мерино|ангор", re.I)
ШОВК = re.compile(r"шовк|silk", re.I)
текст = lambda o: (П(o).get("склад") or "") + " " + o["назва"]
род = C.Counter(П(o).get("матеріал_родина") for o in одяг)
print("матеріал_родина: %s" % dict(род.most_common(8)))
for р, слово in (("вовна", ВОВНА), ("шовк", ШОВК)):
    тут = [o for o in одяг if П(o).get("матеріал_родина") == р]
    без = [o for o in тут if not слово.search(текст(o))]
    print("  «%s» %d, з них без жодного такого волокна в складі й назві %d (%.0f %%), напр. %s"
          % (р, len(тут), len(без), 100 * len(без) / max(1, len(тут)),
             [(П(o).get("склад") or "")[:40] for o in без[:2]]))
