# -*- coding: utf-8 -*-
"""КЛАС КОЛЬОРУ У ВЕТО (рядок 171). Модель кладе в `вето.кольори` слово класу
(«темні кольори», тестувальниця Ір: «Можна яскравий верх — куртку чи жакет, не
темного кольору»), а єдиним читачем був підрядковий пошук: основа фрази («темні
кольо») у назві, типі, тканині й назві кольору речі. Такого підрядка нема в жодній
речі — у діагнозі прогону жодного «вето людини: темні кольори», а над картками
код писав «Твої межі враховано: темні кольори». Проба міряє на ПОВНОМУ каталозі,
скільки речей знімає кожне слово класу ДО (підрядок) і ПІСЛЯ (вимір речі), і
скільки з них рятує слот її слів. Запуск: cd джерела && python3 проби/kolir_klas_171.py"""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import фід_каталог as ФК, feed as Ф, колір_річ as КР, паспорт_нагоди as ПН
ІР = "Можна яскравий верх — куртку чи жакет, не темного кольору"
ПОЛЯ = ("назва", "тип", "тканина", "візерунок", "колір_назва", "колір_назва_фото", "колір_ім")
СЛОВА = ["темні кольори", "світлі відтінки", "яскраві кольори", "пастельні тони", "приглушені кольори"]
каталог = ФК._прочитати_каталог(Ф.каталог_на_диску())["каталог"]
підрядком = lambda r, w: w[:max(4, len(w) - 2)] in " ".join(str(r.get(k) or "") for k in ПОЛЯ).lower()
слоти = ПН.вето_слоти(ІР, ["темні кольори"])["темні кольори"]
разом = [0, 0]
for w in СЛОВА:
    клас = КР.клас_кольору(w)
    до = sum(1 for r in каталог if підрядком(r, w))
    після = [r for r in каталог if КР.річ_у_класі(r, клас) is True]
    разом[0] += до; разом[1] += len(після)
    print("  %-20s → клас «%s» · знято з каталогу: ДО %d → ПІСЛЯ %d (%.1f %%)"
          % (w, клас, до, len(після), 100.0 * len(після) / len(каталог)))
у_слоті = [r for r in каталог if КР.річ_у_класі(r, "темні") is True and r.get("слот") in слоти]
темних = разом[1] and sum(1 for r in каталог if КР.річ_у_класі(r, "темні") is True)
print("речей у каталозі %d · слово класу знімало ДО разом %d, ПІСЛЯ разом %d" % (len(каталог), разом[0], разом[1]))
print("   слот її слів «%s» → %s: темних під межею %d із %d, решту %d вона не згадувала"
      % (ІР[:38], ", ".join(слоти), len(у_слоті), темних, темних - len(у_слоті)))
читачі = [(w, ПН.читач_вето("кольори", w)) for w in ("темні кольори", "чорний", "мокрий асфальт")]
print("   читач слова: " + " · ".join("«%s» → %s" % (w, ч or "НЕМА — рядок меж його не називає") for w, ч in читачі))
assert разом[0] == 0, "підрядок щось таки знаходив — тоді ДО було не нулем"
assert разом[1] > 0 and len(у_слоті) > 0, "вимір не знайшов жодної речі класу"
assert читачі[0][1] and читачі[1][1] and not читачі[2][1], "читачі класу/лексикону/невідомого слова збилися"
