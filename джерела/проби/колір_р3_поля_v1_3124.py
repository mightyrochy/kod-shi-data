# -*- coding: utf-8 -*-
"""КОЛІР-ФІД-3 (рядок 3124): поля жнив v1 у записах КОЛІР-Р3 і що з них доходить до каталогу (`каталог_повний`).
Друкує: записів Р3 з полями v1 на верхньому рівні (опис/крій/довжина…) і в `з_v1`; у каталозі серед речей
із записом Р3 — колір «hex+опис» (опис v1 про інший кадр), крій і довжина з фото, `фото_опису` не той кадр,
що описав опис; і речі Р3 з крієм/довжиною v1, які ворота впевненості Р3 знімають, хоч v1 свої ворота пройшов.
Запуск із джерела/: python3 проби/колір_р3_поля_v1_3124.py"""
import sys, collections as K
sys.path.insert(0, "."); import feed as F, фід_каталог as ФК, фід_збагачення as ФЗ
F.каталог_на_диску("каталог_повний.xml")
зб = ФЗ.читати_збагачення()
ПОЛЯ = ("опис", "крій", "довжина", "матеріал", "блиск", "візерунок", "формальність", "тип_запиту", "фото_номер")
р3 = {k: v for k, v in зб.items() if isinstance(v, dict) and v.get("колір_р3")}
print("записів Р3:", len(р3), "· з полями v1 на верхньому рівні:", sum(any(п in v for п in ПОЛЯ) for v in р3.values()),
      "· з `з_v1`:", sum("з_v1" in v for v in р3.values()),
      "· модель v1 на верхньому рівні:", sum(not str(v.get("модель")).startswith("маска") for v in р3.values()))
кат = [r for r in ФК._прочитати_каталог("каталог_повний.xml", 0)["каталог"] if r["id"] in р3]
зі = [r for r in кат if r.get("збагачення")]
v1 = lambda і: р3[і].get("з_v1") or {п: р3[і][п] for п in ПОЛЯ + ("фото",) if п in р3[і]}
print("у каталозі речей з записом Р3:", len(кат), "· зі збагаченням:", len(зі))
print("  записів Р3, де колір_збагачення бере слово з опису («hex+опис»):",
      sum(ФЗ.колір_збагачення(v)[2] == "hex+опис" for v in р3.values() if ФЗ._збагачення_придатне(v)),
      "· крій з фото:", sum(r.get("крій_джерело") == "фото" for r in кат),
      "· довжина з фото:", sum(r.get("довжина_джерело") == "фото" for r in кат),
      "· фото_слот:", sum(r.get("фото_слот") is not None for r in кат))
з_ф = [r for r in кат if r.get("крій_джерело") == "фото" or r.get("довжина_джерело") == "фото"]
print("  з них крій/довжина v1 на кадрі ≠ кадру Р3:", sum(v1(r["id"]).get("фото") != р3[r["id"]].get("фото") for r in з_ф),
      "· `фото_опису` — не кадр v1:", sum(r.get("фото_опису") != v1(r["id"]).get("фото") for r in з_ф))
ж = [r for r in кат if not r.get("збагачення") and (v1(r["id"]).get("впевненість") or 0) >= ФЗ.ЗБАГАЧЕННЯ_ПОРІГ]
print("  речі без збагачення, чий v1 ворота пройшов (впевненість v1 ≥ поріг):", len(ж),
      "· з крієм v1:", sum(bool(v1(r["id"]).get("крій")) for r in ж),
      "· з довжиною v1:", sum(bool(v1(r["id"]).get("довжина")) for r in ж),
      "(впевненість v1 у записі:", "є)" if any("впевненість" in v1(і) for і in р3) else "нема — злиття її стерло)")
