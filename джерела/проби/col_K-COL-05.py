# -*- coding: utf-8 -*-
"""K-COL-05 (правило відлуння) — від «нікуди» до рядка у вердикті.

Корпус (тема-4:301 → K-COMP-05): акцент або ПОВТОРЮЄТЬСЯ у другій рознесеній
зоні, або є свідомим фокусом; сирота читається як шум. FORCE: `default`
(знижено зі `strong`, прогін 2: порогу «≥2» джерело не дає).
Емітент `колір_образу.відлуння` стоїть за гейтом площі в `суд_образу.review`, а
походження площі на живому вході не ставить ніхто — правило лишало слід у брифі
(`brief.відлуння`) і не судило жодного образу.
ПІСЛЯ: `pipeline.бюджет_і_відлуння` групує кольори образу за дугою 45° (те саме
рішення, що в `колір_образу.відлуння`: сусідні тони — один голос) і рахує ЗОНИ;
«малість» сироти міряє клас слота, а не площа, і це сказано в `ламається`.
ФОКУС-1 (02.10.2026): акцент у слоті, якому схема дала роль акценту, і в її дузі тону —
оголошений фокус (K-COMP-05 «unless the bag is the declared focus»): сироти нема. Тому
сирота тут — кольорова сумка ПОЗА дугою схеми; у дузі — рядка нема (друкується фактом).
Запуск із теки `джерела`: `python3 проби/col_K-COL-05.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import pipeline as PL, реєстр_правил as РЕЄСТР

вх, r, кат, спец = ПВ.стенд(гілка=0)
нейтраль = lambda L, C, h, _: PL._нейтральний_тон(h, C, L)
кольоровий = lambda L, C, h, _: not PL._нейтральний_тон(h, C, L) and C >= РЕЄСТР.C["hi_C"]
# ВЕЛИКІ СЛОТИ — НЕЙТРАЛЬНІ, АКЦЕНТ — В ОДНОМУ АКЦЕНТНОМУ: це і є сирота.
база = [(с, ПВ.з_каталогу(кат, с, нейтраль)) for с in ("верх", "низ", "взуття")]
import суд_ремесло as СР
_сх = lambda x: bool(СР.слоти_акценту_схеми([dict(x, слот="сумка")], спец.get("слоти") or {}))
сирота = ПВ.з_каталогу(кат, "сумка", lambda L, C, h, x: кольоровий(L, C, h, x) and not _сх(x))
взяті = [(с, x) for с, x in база if x] + ([("сумка", сирота)] if сирота else [])
for с, x in взяті:
    L, C, h = ПВ.lch(кат, x["id"])
    print("   %-8s «%s» L%.0f C%.0f h%.0f · сім'я %s"
          % (с, x["назва"][:34], L, C, h, PL._сім_я_кута(h) if C >= 10 else "нейтраль"))
зн, _ = ПВ.знахідки(вх, [x["id"] for _, x in взяті])
print("ФАКТ · K-COL-05: %s" % ПВ.рядок(зн, "K-COL-05"))
z = next((x for x in зн if x.get("правило") == "K-COL-05"), None)
assert z, "єдиний акцент в акцентному слоті не дав K-COL-05"
assert z["сила"] == "default" and z["сила_нп"] == 0.5, z          # корпусна сила прогону 2
assert z["регістр"] == "репліка" and z["ремонт"], z
# НОСІЙ АКЦЕНТУ — ТИМ САМИМ НОМЕРОМ, ЯКИЙ БАЧИЛА МОДЕЛЬ (27.09.2026, рядок 173).
# `вердикт_моделі` перекладає `речі` знахідки в нумерацію пулу («#N·MM», `номер_речі`),
# бо саме її бачить модель; сирий id лишається тільки для речі поза пулом. Проба доти
# рівняла з id і через те червоніла, не бачачи жодної поломки продукту: носій названий
# правильно, лише іншою — чинною — адресою.
import вердикт_моделі as ВМ
from пакет_моделі import номери_речей
_ном = номери_речей(r["кандидати"])[0]
assert z["речі"] == [ВМ.номер_речі(сирота["id"], _ном)], (z, ВМ.номер_речі(сирота["id"], _ном))
print("       ремонт: %s" % z["ремонт"])
