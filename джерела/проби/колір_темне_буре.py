import sys; sys.path.insert(0, ".")
import colorspace as cs
import колір_річ as КР

бурі = ("#392018", "#482a21", "#6d3d2e", "#503633")
вино = ("#2d1216", "#44171c", "#391b20")
for hx in бурі:
    assert КР.нейтраль(cs.hx(hx)) == "тепла", hx
for hx in вино:
    assert КР.нейтраль(cs.hx(hx)) is None, hx
assert КР.нейтраль(cs.hx("#000000")) == "ахроматична"
а, б = ({"lab": cs.hx(hx)} for hx in ("#44171c", "#5c343c"))
assert КР.відношення(а, б, "same_hue") == "так"
assert КР.акцент_меж(а) == КР.акцент_меж(б) == "так"
print("бурі — тепла; вино — колір; 505 — без сироти")
