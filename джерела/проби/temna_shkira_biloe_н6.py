"""Н6: скільки верхів каталогу карає K-CLR-02 у темношкірої жінки (звіт Research §4.3, Flusser: біле біля
темного обличчя — доречний контраст). Рішення власника (CLAUDE.md п.18, рядки 265, 1402): світлі й чисті біля
глибокої шкіри — підказка; рівень контрасту — не лише ΔL волосся↔шкіра (`face_contrast.контраст_рис`).
На верхах `каталог_повний.xml` (усі з кольором і окремо світлі L* ≥ 80): скільки дістає «вище власного
контрасту», «нижче» чи «ok» — на синтетичних профілях з тим самим чорним волоссям і різною шкірою. Далі ж4
(L*28): білий верх — підказка без ремонту й запиту і під мисматчем; рівні мисматчу — її рівень. З `джерела`."""
import json, sys, collections; sys.path.insert(0, ".")
import bridge as B, outfit as O, колір_образу as K, colorspace as cs, палітра_специфікація as С
B.виклик("запити", json.dumps(json.load(open("стенд_вх.json", encoding="utf-8")), ensure_ascii=False))
усі = [dict(r, hex=r.get("hex") or cs.hex_з_lab(tuple(r["lab"])))
       for r in B.каталог_останнього_пакета() if r.get("слот") == "верх" and r.get("lab")]
світлі = [r for r in усі if r["lab"][0] >= 80.0]
верх = lambda h="#f4f4f0": O.елементи([dict(id="в", слот="верх", hex=h)])
def лічба(верхи, ос):
    """(знахідок «вище», знахідок «нижче», без знахідки, набір сил) на цих верхах."""
    c = collections.Counter()
    for r in верхи:
        з = [z for z in K.біля_обличчя(верх(r["hex"]), ос) if z.get("правило") == "K-CLR-02"]
        c[("ok" if з[0]["сила"] == "ok" else ("вище:" if "вищ" in з[0]["суть"] else "нижче:") + з[0]["сила"])
          if з else "нема"] += 1
    return c
print("верхів із кольором %d, з них світлих (L* ≥ 80) %d · волосся чорне L*15" % (len(усі), len(світлі)))
for L_ш in (35.0, 45.0, 50.0, 60.0, 72.0):
    ос = O.контраст_особи(cs.features(cs.hx(cs.hex_з_lab((L_ш, 12.0, 18.0))),
                                      cs.hx(cs.hex_з_lab((15.0, 3.0, 5.0))), cs.hx("#5a3a1e")))
    св, вс = лічба(світлі, ос), лічба(усі, ос)
    print("шкіра L*%.0f ΔL %2.0f (%-8s) світлі: %s · усі верхи: %s" % (L_ш, ос["value_gap"], ос["рівень"],
          dict(sorted(св.items())), dict(sorted(вс.items()))))
    assert sum(св.values()) == len(світлі) and sum(вс.values()) == len(усі)
F4 = cs.features(*(cs.hx(cs.hex_з_lab(l)) for l in ((28., 12., 18.), (8., 3., 5.), (17., 8., 10.))))
ос4, м4 = O.контраст_особи(F4), С.специфікація(F4, С.МИСМАТЧ, ["верх"])["мисматч"]
for мм in (None, м4):
    з = K.біля_обличчя(верх(), ос4, мисматч=мм)[0]
    print("ж4 білий верх, %s: %s, ремонт %s, запит %s" % (мм and "з мисматчем" or "без мисматчу", з["сила"],
          bool(з.get("ремонт")), bool(з.get("запит_у_каталог"))))
    assert з["сила"] == "hint" and not з.get("ремонт") and not з.get("запит_у_каталог")
print("ж4 мисматч: рівень %(рівень_власний)s %(власний).1f → %(рівень_образу)s %(підставлений).1f, "
      "драбина %(драбина_власна).1f → %(драбина).1f" % м4); assert м4["рівень_власний"] == ос4["рівень"]
print("temna_shkira_biloe_н6: зелено (вимір, не гейт)")
