# -*- coding: utf-8 -*-
"""Н6: скільки верхів каталогу карає K-CLR-02 у темношкірої жінки — ЛИШЕ ФАКТ для рішення власника
(17А), правило не чіпано. Звіт Research §4.3 (Flusser, E4): контраст особи = ΔL волосся↔шкіра, і для
шкіри L*≈35 з чорним волоссям він «низький» (20), тож світлий верх (стрибок 35→95) карається — хоча
практики кажуть, що біле тут саме й створює доречний контраст. На верхах `каталог_повний.xml`
(усі з кольором і окремо світлі L* ≥ 80): скільки дістає знахідку «вище власного контрасту», скільки
«нижче», скільки нічого — на синтетичних профілях з тим самим чорним волоссям і різною шкірою.
З теки `джерела`: `python3 проби/temna_shkira_biloe_н6.py`."""
import json, sys, collections
sys.path.insert(0, ".")
import bridge as B, outfit as O, колір_образу as K, colorspace as cs
B.виклик("запити", json.dumps(json.load(open("стенд_вх.json", encoding="utf-8")), ensure_ascii=False))
усі = [dict(r, hex=r.get("hex") or cs.hex_з_lab(tuple(r["lab"])))
       for r in B.каталог_останнього_пакета() if r.get("слот") == "верх" and r.get("lab")]
світлі = [r for r in усі if r["lab"][0] >= 80.0]
ШКІРИ = ((35.0, "темна L*35"), (45.0, "середня L*45"), (60.0, "світліша L*60"), (72.0, "світла L*72"))


def лічба(верхи, ос):
    """(знахідок «вище», знахідок «нижче», без знахідки, набір сил) на цих верхах."""
    c = collections.Counter()
    for r in верхи:
        з = [z for z in K.біля_обличчя(O.елементи([dict(id="в", слот="верх", hex=r["hex"])]), ос)
             if z.get("правило") == "K-CLR-02"]
        c[("вище:" + з[0]["сила"] if "вище" in з[0]["суть"] else "нижче:" + з[0]["сила"]) if з else "нема"] += 1
    return c


print("верхів із кольором %d, з них світлих (L* ≥ 80) %d · волосся в усіх профілях чорне L*15"
      % (len(усі), len(світлі)))
for L_ш, підпис in ШКІРИ:
    ос = O.контраст_особи(cs.features(cs.hx(cs.hex_з_lab((L_ш, 12.0, 18.0))),
                                      cs.hx(cs.hex_з_lab((15.0, 3.0, 5.0))), cs.hx("#5a3a1e")))
    св, вс = лічба(світлі, ос), лічба(усі, ос)
    print("%-14s ΔL %2.0f (%-8s) світлі: %s · усі верхи: %s"
          % (підпис, ос["value_gap"], ос["рівень"],
             dict(sorted(св.items())), dict(sorted(вс.items()))))
    assert sum(св.values()) == len(світлі) and sum(вс.values()) == len(усі)
print("temna_shkira_biloe_н6: зелено (вимір, не гейт — рішення власника 17А)")
