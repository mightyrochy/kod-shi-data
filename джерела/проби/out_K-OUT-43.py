"""K-OUT-43 (вкоротити можна, подовжити ні) — БЕЗ ВХОДУ, і тепер це видно.

ЩО ВИМІРЯНО. Правило живе всередині смуги близькості K-OUT-03 (10 см): воно
називає, який із двох боків майже-збігу ремонтується. Але єдине джерело краю на
живому шляху — РІВЕНЬ ТІЛА зі слова назви: `край_джерело="річ"` (виміряна
довжина виробу) не ставить жоден писач, бо сантиметрів довжини фід не несе.
Сітка рівнів на тілі 168 дає найменший ненульовий крок 14.3 см — поза смугою.
Отже виміряний висновок недосяжний за побудовою, а нульова відстань (однакові
рівні) веде в гілку «спір джерел», яка навмисно нейтральна.
ЧЕСНО ВИМКНЕНО: пункт 17 чекліста надлишку стоїть у стані «без входу», і це
доїжджає у `вердикт.образи[0].чекліст.надлишок.без_входу`."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, outer as OU, fit as ПС, суд_образу as СУД

T = ПС.тіло(168, {"плечі": 98, "груди": 92, "талія": 74, "стегна": 99, "високе_стегно": 88})
рівні = [(р, OU.край_см(dict(довжина_рівень=р), T)[0]) for р in OU.РІВЕНЬ_КРАЮ]
см = sorted(v for _, v in рівні if v is not None)
кроки = [round(b - a, 1) for a, b in zip(см, см[1:]) if b - a > 0.01]
print("рівні краю на тілі 168:", ", ".join("%s %.1f" % (р, v) for р, v in рівні if v))
print("кроки сітки: %s · найменший %.1f см проти смуги K-OUT-03 %.0f см"
      % (кроки, min(кроки), OU.C["смуга_близькості_см"]))
пункт = next(p for p in СУД.ЧЕКЛІСТ_НАДЛИШКУ if "K-OUT-43" in p[2])
print("пункт чекліста:", пункт[0], "·", пункт[1], "· вхід:", пункт[3])

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
вх["сценарій"].update(темп_c=8, опади="ні")
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
к = з["кандидати"]
взяти = lambda сл, ум: next((кат[r["id"]] for r in (к.get(сл) or [])
                             if r["id"] in кат and ум(кат[r["id"]])), None)
ід = [r["id"] for r in (взяти("верхній_шар", lambda c: c.get("довжина_рівень")),
                        взяти("сукня", lambda c: c.get("довжина_рівень")),
                        взяти("взуття", lambda c: True)) if r]
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
п17 = next((p for p in ((вм.get("чеклісти") or {}).get("надлишок") or [])
            if p.get("пункт") == пункт[0]), None)
print("речей із край_джерело=«річ» у каталозі:",
      sum(1 for c in кат.values() if c.get("край_джерело") == "річ"))
print("стан пункту 17:", (п17 or {}).get("стан"), "· у вердикті без_входу:",
      ((о.get("чекліст") or {}).get("надлишок") or {}).get("без_входу"))
print("K-OUT-43 у знахідках:",
      [z["правило"] for z in (о.get("знахідки") or []) if z["правило"] == "K-OUT-43"] or "нема — входу нема")
