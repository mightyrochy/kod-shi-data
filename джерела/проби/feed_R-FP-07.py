# -*- coding: utf-8 -*-
"""R-FP-07 — «Nickname-class attributes are the highest-risk output… Require a
confidence signal on nickname outputs specifically, or drop the class».

Крій — атрибут-прізвисько: «bodycon», «wrap» — це НАЗВА форми, не її вимір. У
записі речі лежать ДВА свідчення про нього (слово крамниці й крій із фото), і
доти їх не звіряв ніхто, хоч `silhouette.КРОЇ` переводить переможця в
сантиметри припуску. Проба рахує, на скількох речах свідки розходяться і
скільки з них силует судить як вимір, і показує вихід правила до/після."""
import sys, pathlib, collections
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, silhouette as S, суд_образу as С

кат = Ф._прочитати_каталог(Ф.каталог_на_диску("каталог_повний.xml"), ліміт_фото=0)["каталог"]
обидва = [c for c in кат if isinstance(c.get("крій_спір"), dict) or (
    c.get("крій_крамниці") and c.get("крій") == c.get("крій_крамниці"))]
спір = [c for c in кат if isinstance(c.get("крій_спір"), dict)]
як_вимір = [c for c in спір if c.get("крій") in S.КРОЇ]
# ⚠ знаменник — записи, де В ЗАПИСІ лишили слід ОБИДВА свідки. Згода в гілці
# «param силует» сліду не лишає (фото не перезаписує поля), тож частка нижче —
# не частка незгоди по каталогу, а частка по видимих парах. Число спорів точне.
print("записів %d · пар свідків, видимих у записі, %d · розходяться %d (%.0f %% пар)"
      % (len(кат), len(обидва), len(спір), 100 * len(спір) / len(обидва)))
print("   свідок крамниці: %s" % dict(collections.Counter(
    c["крій_спір"]["свідок_крамниці"] or "слова нема" for c in спір)))
print("   із них силует судить як ВИМІР (крій → ease/форма в см): %d" % len(як_вимір))
assert спір and len(як_вимір) == len(спір), "кожен спір іде в сантиметри припуску"

зр = next(c for c in спір if c["крій_джерело"] == "фото")
print("зразок: «%s» — крамниця «%s» (%s), фото «%s»"
      % (зр["назва"][:38], зр["крій_спір"]["крамниця"],
         зр["крій_спір"]["свідок_крамниці"], зр["крій_спір"]["фото"]))

річ = dict(зр, hex="#808080")
z_до = С.свідки_крою([{k: v for k, v in річ.items() if k != "крій_спір"}])
print("до:  знахідок про крій %d — свідки лежать поруч, ніхто не звіряє" % len(z_до))
assert not z_до
z = С.свідки_крою([річ])
assert len(z) == 1
z = z[0]
print("після: %s [%s] сила_нп %s, блокує=%s" % (z["правило"], z["регістр"], z["сила_нп"], z["блокує"]))
print("   %s" % z["суть"][:110])
assert z["регістр"] == "питання" and not z["блокує"], "сигнал упевненості, не інший вердикт"
assert зр["крій_спір"]["крамниця"] in z["суть"] and зр["крій_спір"]["фото"] in z["суть"]
# згода двох свідків мовчить: правило не говорить там, де говорити нема про що
згода = next(c for c in кат if c.get("крій_крамниці") and c["крій"] == c["крій_крамниці"])
print("згода свідків («%s»): знахідок %d — правило мовчить"
      % (згода["крій"], len(С.свідки_крою([dict(згода, hex="#808080")]))))
assert not С.свідки_крою([dict(згода, hex="#808080")])
