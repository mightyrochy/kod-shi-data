ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as FK, фід_кадр_колір as FKK, фід_збагачення as FZ, verify as V, дріт_моделі as ДМ
def прогін(функція):
    FK.слово_варіанта = FKK.слово_варіанта = функція
    return {r["id"]: r for r in FK._прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"]}
ДО = types.ModuleType("фід_варіант_до"); ДО.__file__ = os.path.join(ТУТ, "фід_варіант.py")
exec(subprocess.run(["git", "show", "6a486dca:джерела/фід_варіант.py"], capture_output=True, text=True, check=True).stdout, ДО.__dict__)
import фід_варіант as ФВ
після, до = прогін(ФВ.слово_варіанта), прогін(ДО.слово_варіанта)
код = lambda r: ДМ.колір_код(r.get("колір_назва"))[0]   # код `color` речі в пакеті (`дріт_моделі`)
зміни = [(до[і], r) for і, r in після.items() if і in до and код(до[і]) != код(r)]
лік, близькі = collections.Counter(), 0
for а, б in зміни:
    с = V.слово_крамниці(а.get("колір_назва") or "")
    в = (V.ЛЕКСИКОН.get(с["ім"]) if с else None)
    близьке = bool(в) and V.перевірити(FZ._центр_вікна(в), ім=V.назва_кольору(б.get("назва") or ""))["вердикт"] == "прийнято"
