# -*- coding: utf-8 -*-
"""Рядок 44 БЕКЛОГ: «фото крамниці може не відповідати назві» на речах, де фото
збігається. Гіпотеза була — номер «#N·код» резолвиться в РІЗНІ id там, де
будується промпт опису (`опис` бере номери з `вибір.номери`), і там, де
розбирається відповідь (`від_моделі` будує пул наново). Шов іде живцем:
вердикт → вибір → опис → розбір, три сіди. Резолвінг судиться по обох половинах
розбору (`фото_не_ті` + `фото_не_ті_знято`: доказ коду знімає позначку, не id).
Друге число — чи просить код заповнити «фото_не_те» там, де знімків НЕМА (перепис мови).
Запуск із теки `джерела`: `python3 проби/foto_ne_te_шов.py`."""
import sys, os, json, tempfile, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B, pipeline as PL, feed as F

вх = json.load(open("стенд_вх.json", encoding="utf-8"))
вх["каталог"] = F.каталог_на_диску("каталог_brief.xml")
вх["кеш_кольорів"] = os.path.join(tempfile.gettempdir(), "кеш_живого_шляху.json")
if not os.path.exists(вх["кеш_кольорів"]): json.dump({}, open(вх["кеш_кольорів"], "w"))
міст = lambda ім, d: json.loads(B.виклик(ім, json.dumps(d, ensure_ascii=False)))
опис_відп = lambda н: json.dumps(dict(версія="1", текст="проза для жінки.",
                                      як_носити=[], фото_не_те=н), ensure_ascii=False)
розбіжних = 0
for сід in (1, 2, 3):
    в0 = dict(вх, сід=сід)
    пул = json.loads(міст("запити", в0)["руки"]["1"])["пул"]
    # із сумкою й шарфом: без них вибір ріже структурний блокер, і шва не видно
    ном = [пул[с][0]["н"] for с in ("сукня", "взуття", "сумка", "шарф")
           if (пул.get(с) or [{}])[0].get("н")]
    в1 = міст("від_моделі", dict(в0, текст_моделі=json.dumps(
        dict(версія="1", образи=[dict(ід="о1", підпис="шов 44", речі=ном)]), ensure_ascii=False)))
    в3 = міст("від_моделі", dict(в0, ітерація=2, відповідь="ВИБІР_V1", вибір_над=в1["вибір_над"],
                                 текст_моделі=json.dumps(dict(версія="1", обрано="о1"))))
    вб = в3["вибір"]                     # id → «#N·код»: ТИМИ номерами й піде промпт опису
    оп = міст("опис", dict(в0, речі=вб["ід"], номери=вб["номери"]))
    показані = [р["н"] for р in оп["опис"]["образ"]["речі"]]
    в4 = міст("від_моделі", dict(в0, ітерація=2, відповідь="ОПИС_ВІДПОВІДЬ_V1",
                                 ід=вб["ід"], текст_моделі=опис_відп(показані)))
    # Доказ коду (`pipeline.фото_доведено_коду`) відводить частину РЕЗОЛЬВНУТИХ
    # речей у `фото_не_ті_знято`; шов міряє номер→id, а не кому позначка дісталась.
    знято = {з["id"] for з in в4["опис"]["фото_не_ті_знято"]}
    вийшло, чекали = set(в4["опис"]["фото_не_ті"]) | знято, set(вб["ід"])
    розбіжних += len(вийшло ^ чекали)
    print("сід %d: речей %d · номери промпта %s · назад %d/%d (знято доказом %d) · розбіжних %d"
          % (сід, len(чекали), показані, len(вийшло & чекали), len(чекали), len(знято),
             len(вийшло ^ чекали)))
м = PL.мова_повтор(dict(можна_видавати=False, порушення=[dict(правило="R-LNG-UA", що="рос.")]))
просять = "ПОРОЖНІМ" not in str((м or {}).get("фото"))
print("РОЗБІЖНИХ НА 3 СІДАХ: %d — номер дає той самий id на обох кроках" % розбіжних)
print("перепис мови (знімків у ньому нема) просить заповнити «фото_не_те»:", "ТАК" if просять else "НІ")
sys.exit(1 if розбіжних or просять else 0)
