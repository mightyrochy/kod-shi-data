from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).parents[1]))
import мовний_шар as МШ
import протокол as П

файли = list(Path(__file__).parents[2].glob("аудит/живий_пачка2/ДО/П*/VIDPOVIDI/*.txt"))
було = стало = різних = втрачено = 0
for файл in файли:
    текст = файл.read_text().split("── ВІДПОВІДЬ ", 1)[-1].split(" ──\n", 1)[-1]
    старе = П.розбір(текст)[0]
    імʼя = файл.name
    схема = next((с for с in ("ОБРАЗИ_V1", "ВИБІР_V1", "ОПИС_ВІДПОВІДЬ_V1") if с in імʼя), None)
    if схема:
        нове = П.розбір_за_схемою(текст, схема)[0]
    elif "мовний_шар" in імʼя:
        нове = МШ._обʼєкт(текст, [])[0]
    else:
        поля = (("items",) if "перелік_речей" in імʼя else
                 ("scheme",) if "вибір_палітри" in імʼя else ())
        нове = П.розбір_останній(текст, поля)[0]
    було += старе is not None
    стало += нове is not None
    різних += старе != нове
    втрачено += старе is not None and нове is None
print(f"файлів={len(файли)} було_розібрано={було} стало_розібрано={стало} різних={різних} було_валідне_втрачено={втрачено}")
