# -*- coding: utf-8 -*-
"""Н-4: наскільки надійний ВИМІРЯНИЙ hex речі — ΔE00 між двома її власними кадрами.

Звіт Research про композицію каже, що похибка кольору з фото «значно більша за
≈1 ΔE», але числа не дає. K-ACC-10 («дві акцентні поверхні збігаються точно»)
стоїть на порозі ΔE00 ≤ 2 саме по виміряних hex, тож питання не теоретичне:
якщо два кадри ОДНІЄЇ речі розходяться далі за поріг, правило міряє шум.
Вхід — `каталог_кадри.json.gz` (#409, qwen3-vl + SAM): на кожну річ до 6 кадрів
із власним `lab`. Пари беруться в межах ОДНОГО кореня імені файлу (…_blue_2 і
…_blue_3), щоб не порівнювати різні кольорові варіанти того самого SKU.
Запуск із теки `джерела`: `python3 проби/н4_друге_фото_de.py`."""
import sys, pathlib, gzip, json, re, itertools, statistics
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import colorspace as CS

КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
ПОРІГ_ACC10, ПОРІГ_COL06 = 2.0, 6.0


def корінь_файлу(ф):
    б = ф.rsplit("/", 1)[-1].rsplit(".", 1)[0]
    б = re.sub(r"_[0-9a-f]{8}-[0-9a-f-]{20,}$", "", б)      # shopify-суфікс
    return re.sub(r"[_-]?\d+$", "", б)                       # хвостовий номер кадру


записи = json.load(gzip.open(КОРІНЬ / "каталог_кадри.json.gz", "rt", encoding="utf-8"))["записи"]
пари = []
for кадри in записи.values():
    гр = {}
    for к in кадри:
        if к.get("lab"):
            гр.setdefault(корінь_файлу(к["файл"]), []).append(к)
    for g in гр.values():
        пари += [CS.de00(tuple(a["lab"]), tuple(b["lab"])) for a, b in itertools.combinations(g, 2)]
пари.sort()
над = lambda п: 100.0 * sum(1 for x in пари if x > п) / len(пари)
print("ФАКТ · речей із кадрами %d, пар «той самий варіант» %d" % (len(записи), len(пари)))
print("ФАКТ · ΔE00 між двома кадрами однієї речі: медіана %.1f, p90 %.1f, максимум %.1f"
      % (statistics.median(пари), пари[int(0.9 * len(пари))], пари[-1]))
print("ФАКТ · понад поріг K-ACC-10 (ΔE00 %.1f): %.1f %% пар; понад поріг K-COL-06 (ΔE00 %.1f): %.1f %%"
      % (ПОРІГ_ACC10, над(ПОРІГ_ACC10), ПОРІГ_COL06, над(ПОРІГ_COL06)))
assert statistics.median(пари) > ПОРІГ_ACC10, "медіана шуму нижча за поріг K-ACC-10 — вимір hex надійний"
