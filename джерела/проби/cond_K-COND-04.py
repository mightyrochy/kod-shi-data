# -*- coding: utf-8 -*-
"""K-COND-04: вага слота ключується на ВІДСТАНЬ ОГЛЯДУ. Один образ, дві сцени.

ДО: вага слота одна на всі нагоди (шарф 1.00 і взуття 0.00 і за столом в офісі, і
на сцені), тож сили K-CRA-07 (самотній метал) і K-COL-06-M / K-CLR-05 (метал проти
температури особи) від нагоди не залежали. ПІСЛЯ: `місце`+`формат`+`нагода` → вісь,
вісь → вага, вага → сила, а на «повний зріст» — і саме рішення про метал."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, composer as КМ, outfit as O, fit as ПС
import суд_образу as СО, colorspace as cs, дистанція as Д
вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml"); вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
T = ПС.тіло(float(вх["зріст"]), {k: float(v) for k, v in вх["обхвати"].items()})
F = cs.features(cs.hx(вх["шкіра"]), cs.hx(вх["волосся"][0]), cs.hx(вх["очі"]))
пер = lambda сл, м=None: next(c for c in кат if c.get("слот") == сл
                              and (м is None or c.get("метал") == м))
сирі = [пер("сукня"), пер("взуття"), пер("шарф"),
        пер("брошка", "срібло"), пер("прикраси", "золото")]
драп = {"білий": "оптичний", "нейтралі": "не бачу різниці"}
сил = lambda зн, ід, м="": next((z.get("сила_нп") or "утримано" for z in зн
                                 if z["правило"] == ід and (not м or м in z["чому"])), "—")
print("підтон %s · образ %s · срібна брошка біля обличчя, золото на руці"
      % (F["шкіра"].get("undertone"), "+".join(c["слот"] for c in сирі)))
for підпис, сц in [("до: одна вага на всі сцени", {}),
                   ("офіс · приміщення", dict(місце="офіс", формат="приміщення")),
                   ("сцена · повний зріст", dict(місце="сцена", формат="просто неба"))]:
    д = Д.з_сценарію(сц)["дистанція"]
    речі = [КМ._у_річ(dict(c), c["слот"], T, д) for c in сирі]
    зн = СО.метали(O.елементи(речі, дистанція=д), F, "uncontrolled", драп, "conventional", речі)
    n = {r["слот"]: r["near"] for r in речі}
    print("%-26s дистанція=%-13s вага слота: шарф %.2f · взуття %.2f · брошка %.2f\n"
          "%-26s K-CRA-07 срібло %s / золото %s · K-COL-06-M %s · K-CLR-05 %s"
          % (підпис, д, n["шарф"], n["взуття"], n["брошка"], "", сил(зн, "K-CRA-07", "срібло"),
             сил(зн, "K-CRA-07", "золото"), сил(зн, "K-COL-06-M"), сил(зн, "K-CLR-05")))
assert Д.з_сценарію(dict(формат="приміщення"))["дистанція"] is None, "здогад заборонено"
print("рядок жінці: " + Д.словами("розмова"))
