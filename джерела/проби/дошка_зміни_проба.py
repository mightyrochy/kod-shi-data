# -*- coding: utf-8 -*-
"""Перевіряє джерело й хронологію повного рядка після заміни та зміни стану."""
import sys, tempfile
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'прилади'))
import згорнути_дошку as згортання


if __name__ == '__main__':
    поля = '<!-- дошка: дата=2026-10-26; рід=процес; попередник=ні; механізм=інше -->'
    кінець = '<!-- дошка: механізм=інше; закриття=корінь; доказ=проба; дата-закриття=2026-10-26 -->'
    рядок = lambda н, с='**ВІДКРИТО**', п=поля: f'| {н} | факт {п} | низька | {с} | доказ | файл | команда |'
    невдалі = []
    with tempfile.TemporaryDirectory() as тека:
        т = Path(тека); (т / 'фрагменти').mkdir()
        згортання.КОРІНЬ, згортання.ДОШКА, згортання.ТЕКА = тека, str(т / 'дошка.md'), str(т / 'фрагменти')
        згортання.КОРЕНІ = str(т / 'корені')
        дошка, фрагмент = Path(згортання.ДОШКА), т / 'фрагменти' / 'проба.md'
        for номер in (6977, 10180):
            for вид in ('заміна', 'стан', 'новий і стан', 'заміна і стан'):
                for джерело in ('', '; виявлено: вигадане', '; виявлено: диспетчер'):
                    початковий = рядок(номер, '**ВІДКРИТО**; виявлено: проба', '' if вид == 'заміна' else поля)
                    дошка.write_text(рядок(1, п='') + ('\n' + початковий if вид != 'новий і стан' else ''), encoding='utf-8')
                    стан = '**ЧАСТКОВО**' + джерело + '; внесено: давнє ' + кінець
                    текст = 'заміна ' + рядок(номер, стан) if вид == 'заміна' else f'стан {номер}: {стан}'
                    if вид in ('новий і стан', 'заміна і стан'):
                        текст = ('' if вид == 'новий і стан' else 'заміна ') + початковий + '\n' + текст
                    фрагмент.write_text(текст, encoding='utf-8')
                    до = дошка.read_bytes(), фрагмент.read_bytes()
                    вади = згортання.згорнути(True)[1]
                    if any('поле виявлено:' in п for п in вади) != (джерело != '; виявлено: диспетчер'):
                        невдалі.append((номер, вид, джерело, вади))
                    assert до == (дошка.read_bytes(), фрагмент.read_bytes())
            дошка.write_text(рядок(1, п='') + '\n' + рядок(номер, п=''), encoding='utf-8')
            фрагмент.write_text('заміна ' + рядок(номер, '**ЧАСТКОВО**; виявлено: диспетчер; внесено: давнє ' + кінець.replace('2026-10-26', '2026-10-25')), encoding='utf-8')
            if not any('поле дата-закриття:' in п for п in згортання.згорнути(True)[1]):
                невдалі.append((номер, 'хронологія заміни без давньої дати'))
    print(f'Зміни: 24 сценарії джерела, 2 ранні закриття; невдалих {len(невдалі)}: {невдалі}')
    assert not невдалі
