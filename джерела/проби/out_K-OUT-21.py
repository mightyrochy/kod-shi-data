# -*- coding: utf-8 -*-
"""K-OUT-21 (обʼєм не гасять обʼємом) — живим шляхом до вердикту.

ДО ПРАВКИ: другий полюс умови порівнювався з українськими літералами
(«широкий»/«кльош»/«палацо»), а поле `крій` несе канонічні значення
`silhouette.КРОЇ` («wide»/«flared»/«culottes»). Жоден низ каталогу умови не
задовольняв — правило мовчало на КОЖНОМУ образі.
ПІСЛЯ: крій читається `outfit.крій_речі`, і на парі «оверсайз-верх + широкий
низ» рядок K-OUT-21 стоїть у `вердикт.образи[0].знахідки`."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, outfit as ОФ, outer as OU

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
вх["сценарій"].update(темп_c=5, опади="ні")
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
к = з["кандидати"]
взяти = lambda сл, ум: next((кат[r["id"]] for r in (к.get(сл) or [])
                             if r["id"] in кат and ум(кат[r["id"]])), None)
верх = взяти("верхній_шар", lambda c: c.get("оверсайз"))
низ = взяти("низ", lambda c: ОФ.крій_речі(c) in OU.ОБʼЄМНІ_КРОЇ)
взуття = взяти("взуття", lambda c: True)
print("верхній шар:", верх["назва"][:52], "· оверсайз")
print("низ:        ", низ["назва"][:52], "· крій", ОФ.крій_речі(низ))
ід = [r["id"] for r in (верх, низ, взуття) if r]
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
зн = ((вм.get("вердикт") or {}).get("образи") or [{}])[0].get("знахідки") or []
р = next((z for z in зн if z.get("правило") == "K-OUT-21"), None)
print("низів каталогу з полем `оверсайз`: %d (поле пише лише `верхні_атрибути`)"
      % sum(1 for c in кат.values() if c.get("слот") == "низ" and c.get("оверсайз")))
print("K-OUT-21 у вердикті:", "НЕМА" if not р else
      "%s %s %.2f · %s" % (р["правило"], р["сила"], р["сила_нп"], р["суть"][:60]))
print("речі рядка:", (р or {}).get("речі"), "· регістр", (р or {}).get("регістр"))
