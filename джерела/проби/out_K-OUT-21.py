# -*- coding: utf-8 -*-
"""K-OUT-21 (обʼєм не гасять обʼємом) — живим шляхом до вердикту.

ЖИВЕ: `верхнє_суд.перевірити` кличе `верхнє_пропорція.обʼєм_пари`, і
`composer._оцінити` читає з `верхній_шар` рівно `ворота`+`преференції` —
K-OUT-21 доходить до `вердикт.образи[0].знахідки` без правки шва.
`measure_theme11.py` рахує ID мертвим лише тому, що ЙОГО ВЛАСНА фікстура
ставить `крій="палацо"`, якого нема в `outfit.СИНОНІМИ_КРОЮ` («кюлоти»→
culottes, «широкі»→wide — «палацо» не додано).

ЩО БУЛО НЕ ТАК У ЦІЙ ПРОБІ: вона шукала низ лише серед `кандидати["низ"]` —
пропозицій `запити` для сценарію business_casual/офіс, а формальність
відсіює всі 24 запропоновані низи до straight/bodycon/fitted/relaxed. Але
`від_моделі` судить БУДЬ-ЯКУ пару з каталогу, не лише кандидатів
(`поза_кандидатами` — інформація, не заборона): у пакеті 224 низи з крієм із
`ОБʼЄМНІ_КРОЇ` (wide 103, a-line 75, flared 39 …). Проба бере низ ПРЯМО З
КАТАЛОГУ ПАКЕТА — так само, як це може зробити модель."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, outfit as ОФ, outer as OU

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
вх["сценарій"].update(темп_c=5, опади="ні")
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
верх = next(c for c in кат if c.get("слот") == "верхній_шар" and c.get("оверсайз"))
низ = next(c for c in кат if c.get("слот") == "низ" and ОФ.крій_речі(c) in OU.ОБʼЄМНІ_КРОЇ)
взуття = next(c for c in кат if c.get("слот") == "взуття")
print("верхній шар:", верх["назва"][:52], "· оверсайз")
print("низ (з каталогу пакета, не з кандидатів):", низ["назва"][:44], "· крій", ОФ.крій_речі(низ))
ід = [c["id"] for c in (верх, низ, взуття)]
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
р = next((z for z in (о.get("знахідки") or []) if z.get("правило") == "K-OUT-21"), None)
print("K-OUT-21 у вердикті:", "НЕМА" if not р else
      "%s %s %.2f · %s" % (р["правило"], р["сила"], р["сила_нп"], р["суть"][:60]))
print("поза_кандидатами:", о.get("поза_кандидатами"), "· речі рядка:", (р or {}).get("речі"))
assert р, "обʼємний верх + обʼємний низ мусить давати K-OUT-21 у вердикті"
