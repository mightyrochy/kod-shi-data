# -*- coding: utf-8 -*-
"""K-PAL-18 (акцент перевіряється, а не призначається) — ціле й далі ціле.

Правило вже мало обидва яруси (`pipeline.акцент_образу` → знахідка з регістром),
і ця сесія його не переписувала. Але вона зачепила те, на чому воно стоїть: пул
(звідки береться «у пулі БУЛО з чого взяти акцент») і `_ремонт_рядком` (звідки
модель читає вихід). Проба стереже обидва: знахідка живе, і її ремонт доїжджає.
Запуск із теки `джерела`: `python3 проби/pal_K-PAL-18.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import pipeline as PL

вх, r, кат, спец = ПВ.стенд(гілка=0)
акцентні = [с for с, v in (спец.get("слоти") or {}).items()
            if isinstance(v, dict) and v.get("роль") == "акцент" and v.get("C")]
print("акцентні слоти схеми «%s»: %s" % (спец.get("схема"), ", ".join(акцентні[:6])))
сл = "сумка" if "сумка" in акцентні else (акцентні[0] if акцентні else None)
Cmin = float(((спец.get("слоти") or {}).get(сл) or {}).get("C", [0, 0])[0]) if сл else 0.0
тьмяна = ПВ.взяти(r, кат, сл, lambda L, C, h, _: C < Cmin) if сл else None
решта = [ПВ.взяти(r, кат, с, lambda *a: True) for с in ("верх", "низ", "взуття")]
print("слот «%s» просить хрому від %.0f · взято річ із хромою %.1f"
      % (сл, Cmin, ПВ.lch(кат, тьмяна["id"])[1] if тьмяна else -1))
if not тьмяна:
    print("ФАКТ · у пулі акцентного слота нема речі, тьмянішої за поріг — акцент не зникає")
    raise SystemExit(0)
ід = [x["id"] for x in [тьмяна] + решта if x]
зн, _ = ПВ.знахідки(вх, ід)
print("ФАКТ · K-PAL-18: %s" % ПВ.рядок(зн, "K-PAL-18"))
z = next((x for x in зн if x.get("правило") == "K-PAL-18"), None)
assert z, "акцент зник і правило змовчало"
assert z.get("ремонт"), "знахідка є, а ремонт до моделі не доїхав"
print("       ремонт: %s" % z["ремонт"])
