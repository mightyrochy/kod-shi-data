"""КОЛІР-ВІКНО-СУД (рядки 3080–3083): речі-слова каталогу пакета стенда (`pal_вердикт.стенд`, statement) — центр вікна
(точка, як судили доти) проти всього вікна («так / ні / невідомо»): нейтраль K-COL-06 (`нейтраль_меж`), у вікнах палітри
K-PAL-09/10 (`у_вікнах_меж`), тон у дузі очей K-PAL-02/13 (`у_дугах_меж`), хрома інтересу K-INT-04/K-CRA-02
(`суд_інтерес.хрома_інтересу`), «у палітрі» кандидата заміни (`річ_з_фото.членство_вікна`); і пари вікон тканинних речей
K-COL-06 — `distinct_fabric` (kL=2, R-COL-11) проти `distinct` (kL=1). Запуск із джерела/: python3 проби/колір_вікно_речі.py"""
import sys, random, collections as K; sys.path.insert(0, "."); sys.path.insert(0, "проби")
import pal_вердикт as ПВ, колір_річ as КР, colorspace as cs, суд_від_моделі as СВ, суд_інтерес as СІ, річ_з_фото as РФ
import колір_простір_стеля as КС
_, _, кат, спец = ПВ.стенд(гілка=0, намір="statement"); П = спец["палітра_практична"]; в = П["вікна"]; Л = K.Counter()
дуги = [a for aa in (в.get("сім_ї") or {}).values() for a in (aa or ())]; очі = (в.get("сім_ї") or {}).get("очі") or []
слова = [x for x in кат.values() if КР.не_вимір(x) and КР.межі_кольору(x) and x.get("lab")]
for x in слова:
    L, C, h = cs.lch(tuple(x["lab"]))
    Л["нейтраль: центр %s → вікно %s" % ("так" if КР.нейтраль(tuple(x["lab"])) else "ні", КР.нейтраль_меж(x))] += 1
    Л["у вікнах палітри: центр %s → вікно %s" % ("так" if СВ._у_вікнах(в, L, C, h) else "ні",
                                                  КР.у_вікнах_меж(x, в["L"], в["C"], дуги, 10.0))] += 1
    if очі: Л["тон у дузі очей: центр %s → вікно %s" % ("так" if КР.у_дугах_меж(dict(lab=x["lab"]), очі, 10.0) == "так" else "ні",
                                                         КР.у_дугах_меж(x, очі, 10.0))] += 1
    Л["хрома інтересу: центр %s → вікно %s" % ("так" if C >= СІ.ІНТЕРЕС_C_МІН and not КР.нейтраль(tuple(x["lab"])) else "ні",
                                                 СІ.хрома_інтересу(x))] += 1
    Л["кандидат «у палітрі»: центр %s → вікно %s" % ("так" if РФ.членство_в_палітрі(x["lab"], П)["стан"] == "у палітрі" else "ні",
                                                     РФ.членство_вікна(x, П)[0])] += 1
Л["речей-слів"] = len(слова); rnd = random.Random(11)
тк = [x for x in слова if КС.тканинна_пара(x.get("текстура"), x.get("текстура"))[0] == 2]
for _ in range(3000 if len(тк) > 1 else 0):
    a, b = rnd.sample(тк, 2)
    Л["пари тканинних вікон: distinct (kL=1) %s → distinct_fabric (kL=2) %s" % (
        КР.відношення(a, b, "distinct"), КР.відношення(a, b, "distinct_fabric"))] += 1
for к_, v in sorted(Л.items()): print("  %-58s %5d" % (к_, v))
