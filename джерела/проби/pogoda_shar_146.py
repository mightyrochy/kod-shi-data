# -*- coding: utf-8 -*-
"""Рядок 146: скільки з 10 образів мають верхній шар і чим код називає його брак.
10 образів — як складає заглушка стенда (`рв6_стенд.js`: сукня або верх+низ, взуття,
сумка, третя річ по колу слотів). «модель» — верхній шар у складеному; «блокер» — образів
із блокером «нема верхнього шару»; «картка» — з верхнім шаром після `повнота_набору`
(добір кодом); K-WEA-01 — регістр «шарів замало». Сцени — `стенд_знімок.СЦЕНАРІЇ` +
«+5, дощ». Запуск: cd джерела && python3 проби/pogoda_shar_146.py"""
import json, sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, pipeline as PL, стенд_знімок as СЗ
СЦЕНИ = dict(СЗ.СЦЕНАРІЇ, **{"+5·дощ·побачення": dict(нагода="побачення", місце="ресторан",
             година=20, темп_c=5, опади="дощ")})
ТРЕТІ = ("верхній_шар", "прикраси", "пояс", "шарф", "головний_убір", "сережки", "намисто",
         "кольє", "браслет", "брошка")
for назва, сц in СЦЕНИ.items():
    вх = dict(json.load(open("стенд_вх.json")), сценарій=сц, випадок=назва)
    к = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["кандидати"]
    кат = {x["id"]: x for x in B.каталог_останнього_пакета()}
    в_ = lambda с, i: к[с][i % len(к[с])]["id"] if к.get(с) else None
    тр = [с for с in ТРЕТІ if к.get(с)]
    образи = [[x for x in ([в_("сукня", i)] if (к.get("сукня") and i % 2) else [в_("верх", i), в_("низ", i)])
               + [в_("взуття", i), в_("сумка", i), в_(тр[i % len(тр)], i) if тр else None] if x]
              for i in range(1, 11)]
    в = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=образи), ensure_ascii=False)))
    ш = lambda ід: any(кат.get(і, {}).get("слот") == "верхній_шар" for і in ід)
    блок = sum(1 for о in (в.get("вердикт") or {}).get("образи") or []
               if any(б.get("код") == "нема_верхнього_шару" for б in (о.get("структура") or {}).get("блокери") or []))
    картки = 0
    for о in (в.get("вердикт") or {}).get("образи") or []:
        п = PL.повнота_набору({"образи": [о]}, кандидати=к, каталог=list(кат.values()),
                              сценарій=dict(сц), дібрати=True)
        картки += bool(п.get("ід")) and ш(п["ід"])
    kw = sorted({"%s %s" % (z.get("регістр"), z.get("сила_нп")) for о in (в.get("вердикт") or {}).get("образи") or []
                 for z in о.get("знахідки") or [] if z.get("правило") == "K-WEA-01" and "замало" in str(z.get("суть"))})
    print("%-22s %+3d °C · модель %d/10 · блокер %d · картка %d/10 · K-WEA-01 «замало»: %s"
          % (назва, сц["темп_c"], sum(map(ш, образи)), блок, картки, ", ".join(kw) or "—"))
