"""Жниварка: слот і стать речі беруться з розбору за повним id (id@магазин) — речі еталона 404_а1, ДО/ПІСЛЯ."""
import json, os, sys
from pathlib import Path
корінь = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(корінь / "zhnyvarka"), str(корінь / "джерела")]
os.environ["ROZBIR_KODY"] = str(корінь / "аудит/розбір_каталогу/404_а1/розбір.json")
import жниварка as Ж
розбір = json.load(open(os.environ["ROZBIR_KODY"], encoding="utf-8")); розбір.pop("причини", None)
def запис(ключ):
    ід, маг = ключ.split("@")
    return dict(id=ід, магазин=маг, url="", слот=None, стать="невідомо")
записи = [запис(к) for к in розбір]
ДО = sum(bool(слот_) for слот_ in (Ж.слот_речі([], "", "")[0] for _ in записи))   # голова #1577: розбір до запису не доходив
for з in записи: Ж.застосувати_розбір(з)
ПІСЛЯ = sum(bool(з["слот"]) for з in записи)
чужий = Ж.застосувати_розбір(dict(запис(next(iter(розбір))), магазин="чужий.test"))
assert not чужий["слот"] and ПІСЛЯ > ДО == 0, (ДО, ПІСЛЯ)
print("жниварка, речі 404_а1: слот відомий ДО %d ПІСЛЯ %d з %d; той самий базовий id іншого магазину: слот %s" % (ДО, ПІСЛЯ, len(записи), чужий["слот"]))
for з in записи[:4]: print("  ", Ж.повний_id(з), "→", з["слот"], з["стать"])
