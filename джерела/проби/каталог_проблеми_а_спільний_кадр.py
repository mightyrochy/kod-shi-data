# -*- coding: utf-8 -*-
"""Реєстр А (рядок 5630), клас А1/А4: кадр жнив — не фото цієї речі. Друкує по крамницях, у скількох
речах кадр, на якому модель міряла колір і поля, (1) сам є спільною картинкою крамниці (≥3 товари —
логотип, банер, чужа річ), (2) не стоїть серед фото фіду цієї речі (узятий зі сторінки товару чи
з іншого розміру) і (3) скільки з (1) мали б колір лише з цього кадру (поле кольору крамниці порожнє).
Запуск: cd джерела && python3 проби/каталог_проблеми_а_спільний_кадр.py"""
import collections, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed as Ф, фід_фото as ФФ
оф = Ф.читати_yml(Ф.каталог_на_диску("каталог_повний.xml"))[0]
зб, сп = Ф.читати_збагачення(), ФФ._спільні_фото(оф)
с = collections.defaultdict(collections.Counter)
for o in оф:
    з, м = зб.get(o["id"]), o.get("магазин")
    к = з.get("фото") if isinstance(з, dict) else None
    if not к:
        continue
    c = с[м]; c["з кадром"] += 1
    if ФФ.чужий_кадр(к, сп.get(м) or {}):
        c["спільний"] += 1; c["спільний, кольору крамниці нема"] += not (o.get("колір_сирий") or o.get("колір_назва"))
    c["не з фіду"] += ФФ._файл_фото(к) not in {ФФ._файл_фото(u) for u in o.get("фото") or []}
р = lambda к: sum(c[к] for c in с.values())
for м, c in sorted(с.items(), key=lambda x: -(x[1]["спільний"] + x[1]["не з фіду"])):
    if c["спільний"] or c["не з фіду"]:
        print("  %-26s з кадром %4d · спільний %3d (без кольору крамниці %3d) · не з фіду %3d"
              % (м, c["з кадром"], c["спільний"], c["спільний, кольору крамниці нема"], c["не з фіду"]))
print("РАЗОМ: речей %d · з кадром жнив %d · кадр — спільна картинка %d (без кольору крамниці %d) · кадр не з фіду %d"
      % (len(оф), р("з кадром"), р("спільний"), р("спільний, кольору крамниці нема"), р("не з фіду")))
