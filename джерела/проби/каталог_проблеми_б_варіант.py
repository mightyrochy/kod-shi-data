"""Реєстр проблем каталогу, напрям Б, клас Б1: слово кольору — чужого варіанта (поле «Колір» — перелік кольорів моделі).
Рядки 142, 4920, 5021–5024. Слово варіанта вибирає код (`фід_варіант`); ФАКТ — скільки записів пройшли цей вибір,
якими доказами, і в скількох вимір кадру картки — іншої сім'ї тону, ніж обране слово (кандидати на чужий варіант).
Сім'ю слова тут рахує проба (міра), а не продукт. Запуск: cd джерела && python3 -W ignore проби/каталог_проблеми_б_варіант.py"""
import collections, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as FK, verify as V
К = FK._прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"]
def сім(сл):
    ім = (V.слово_крамниці(сл or "") or {}).get("ім")
    return V.сім_я_слова(ім) if ім else None
вар = [r for r in К if r.get("колір_варіант")]
дж, інша, крам = collections.Counter(), collections.Counter(), collections.Counter()
for r in вар:
    д = r["колір_варіант"].get("джерело"); дж[д] += 1
    а, б = сім(r.get("колір_назва")), сім(r.get("колір_назва_фото"))
    if а and б and а != б:
        інша[д] += 1; крам[r["магазин"]] += 1
print("ФАКТ · записів %d; слово вибрано з переліку варіантів у %d (%.1f %%): %s" % (
    len(К), len(вар), 100 * len(вар) / len(К), dict(дж.most_common())))
print("ФАКТ · з них вимір кадру картки — іншої сім'ї тону, ніж обране слово: %d (%s); крамниці %s" % (
    sum(інша.values()), dict(інша.most_common()), крам.most_common(6)))
r = next((r for r in К if r["id"].startswith("ж-02639@")), None)
if r:
    print("ФАКТ · ж-02639 (рядок 4920, блакитний джемпер): колір_назва «%s», поле «%s», вимір кадру «%s» %s — %s" % (
        r.get("колір_назва"), (r.get("колір_варіант") or {}).get("поле"), r.get("колір_назва_фото"),
        r.get("колір_hex_фото"), r.get("колір_назва_за_чим")))
