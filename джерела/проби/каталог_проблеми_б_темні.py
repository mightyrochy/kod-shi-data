"""Реєстр проблем каталогу, напрям Б, клас Б3: вимір з фото хибить на темних, металевих і нейтральних речах.
Рядки 3041 (темні темнішають: темно-синє → #08080f), 4750 («шоколадний светр» → чорний), 3123 (підошва й тло → нейтраль),
4920 (блакитне → «срібний»). ФАКТ — виміряні записи, де слово з фото — сім'ї без тону (чорна, сіра, світла нейтраль),
а слово крамниці — хроматичної сім'ї тону, по сім'ях; темні (L* < 25) окремо; і скільки з них код лишив словом крамниці.
Сім'ю слова тут рахує проба (міра), не продукт. Запуск: cd джерела && python3 -W ignore проби/каталог_проблеми_б_темні.py"""
import collections, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as FK, verify as V, colorspace as CS
К = FK.прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"]
def сім(сл):
    ім = (V.слово_крамниці(сл or "") or {}).get("ім")
    return V.сім_я_слова(ім) if ім else None
АХРОМ = {"чорна", "сіра", "світла нейтраль"}            # сім'ї без тону
ф = [r for r in К if r.get("колір_hex_фото")]
хиб, темні, лишено = collections.Counter(), collections.Counter(), 0
for r in ф:
    кр, фото = сім(r.get("колір_назва_крамниці")), V.сім_я_слова(r.get("колір_назва_фото"))
    if not кр or фото not in АХРОМ or кр in АХРОМ:
        continue
    хиб[кр] += 1; лишено += r.get("колір_назва_джерело") == "крамниця"
    if CS.lch(CS.hx(r["колір_hex_фото"]))[0] < 25:
        темні[кр] += 1
print("ФАКТ · виміряних записів %d; слово крамниці хроматичне, а з фото — ахроматичне: %d (%.1f %%)" % (
    len(ф), sum(хиб.values()), 100 * sum(хиб.values()) / len(ф)))
print("ФАКТ · за сім'єю слова крамниці: %s" % хиб.most_common(8))
print("ФАКТ · з них темні (L* < 25): %d — %s; код лишив слово крамниці у %d, узяв фото у %d" % (
    sum(темні.values()), темні.most_common(5), лишено, sum(хиб.values()) - лишено))
