# -*- coding: utf-8 -*-
"""Проба наряду «помада 116» (R-MUA-03): сходинка відтінків помади замість восьми
квадратів нативного вибору кольору, і поділ «рекомендовані тобі / решта» кодом.
ДО: поле губ — `<input type="color">`; Android дає 8 чистих RGB (червоний, ціан,
синій, зелений, маджента, жовтий, чорний, білий), поділу нема зовсім.
Профілі беруться зі сходинок `bridge.чипи()` — не вписані сюди рукою.
Запуск: cd джерела && python3 проби/pomada_116.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge

ч = json.loads(bridge.виклик("чипи", {}))
ПРОФІЛІ = [("світла тепла", ч["шкіра"][5], ч["волосся"][4], ч["очі"][2]),
           ("світла шкіра, темне волосся", ч["шкіра"][5], ч["волосся"][0], ч["очі"][5]),
           ("смаглява тепла", ч["шкіра"][1], ч["волосся"][1], ч["очі"][1])]
без = json.loads(bridge.виклик("помади", {}))
усього = len(без["сходинки"])
print("сходинок усього: %d (було 8 квадратів браузера) · сімей: %d · %s"
      % (усього, len(без["сім_ї"]), " · ".join(без["сім_ї"])))
print("без профілю: поділ=%s · один ряд із %d · «%s»"
      % (без["поділ"]["є"], len(без["поділ"]["решта"]), без["поділ"]["чому"]))
набори = {}
for назва, ш, в, о in ПРОФІЛІ:
    п = json.loads(bridge.виклик("помади", dict(шкіра=ш, волосся=[в], очі=о)))["поділ"]
    набори[назва] = tuple(sorted(п["рекомендовані"]))
    решта = п["решта"]
    print("%-28s рек %2d / решта %2d · сума %2d == %d · ✔ «%s» · ✗ «%s»: %s"
          % (назва, len(п["рекомендовані"]), len(решта),
             len(п["рекомендовані"]) + len(решта), усього,
             (п["рекомендовані"] or ["—"])[0], (решта or ["—"])[0],
             п["причини"].get(решта[0], "—") if решта else "—"))
    assert п["є"] is True and len(п["рекомендовані"]) + len(решта) == усього
різні = len(set(набори.values())) == len(набори)
print("а) рекомендовані РІЗНІ в трьох профілів: %s"
      % ("так" if різні else "НІ — поділ фіктивний"))
print("б) жоден відтінок не зник: сума груп == %d у всіх трьох" % усього)
print("в) без профілю поділу нема: %s" % (без["поділ"]["є"] is False))
assert різні and без["поділ"]["є"] is False
