# -*- coding: utf-8 -*-
"""Е2-промпти · дошка 11371: прилад довжин бачить хвіст режиму фото в `промпт_вибору`.
`python3 джерела/проби/Е2_11371_хвіст_вибору.py` — код 0, коли кожен варіант виміру має рамку й хвіст свого режиму."""
import os, sys, pathlib
кор = pathlib.Path(__file__).resolve().parents[2]
sys.path[:0] = [str(кор / "джерела" / "прилади"), str(кор / "джерела")]
import корінь_е2_промпти as К
from е2_збирання import зібрати_функції
_, модулі, *_ = К.зібрати_все(кор, False)
тексти = {к: т for к, т in зібрати_функції(модулі, К.є_вимогою)[0].items() if "промпт_вибору" in к}
ознака = {"без_фото=False": ("ЧАСТИНА 2 — ТІЛЬКИ ЗОБРАЖЕННЯ", "додано фото людини", "ДВІ ОКРЕМІ ЧАСТИНИ"),
          "без_фото=True": ("ТІЛЬКИ ТЕКСТ, без зображення", "Пиши українською")}
збої = []
for к, т in sorted(тексти.items()):
    режим = next((р for р in ознака if р in к), None)
    нема = [о for о in ознака.get(режим, ("<режиму у варіанті немає>",)) if о not in т]
    print("%-14s %5d симв. · бракує: %s" % (режим, len(т), нема or "—"))
    збої += нема
if len(тексти) != 4 or збої:
    sys.exit("11371: хвіст режиму фото не в приладі (варіантів %d, бракує %s)" % (len(тексти), збої or "режиму"))
sys.stdout.flush()
os._exit(0)   # код виходу — вердикт проби, а не «непрочитано» приладу в чужих файлах
