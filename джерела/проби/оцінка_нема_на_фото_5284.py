# -*- coding: utf-8 -*-
"""Рядок 5284: записані оцінки (`вердикти.txt`, `етапи.суд`) через `відсутнє_на_фото` — рівень до/після.
Запуск: python3 -W ignore проби/оцінка_нема_на_фото_5284.py <вердикти.txt>…  Б4 (є `вхід_прогону`) — ще й повним `суд()`."""
import sys, os, json, copy
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import оцінка_образу as О
import суд_образу as С

підсумок = {"gate_до": 0, "gate_після": 0, "образів": 0}
for шлях in sys.argv[1:]:
    д = json.load(open(шлях, encoding="utf-8"))
    for пр in д["прогони"]:
        for в in пр["вердикти"]:
            е = в.get("етапи") or {}
            з = е.get("суд")
            if not (isinstance(з, dict) and "рівень" in з and з.get("образ")):
                continue
            s = з["суд"]
            о, блок, нема = С.відсутнє_на_фото({"знахідки": s["findings"], "чеклісти": {}}, s["blockers"])
            після = О.рівень(dict(findings=о["знахідки"], blockers=блок))
            лишились = [x["код"] for x in блок] + [x["правило"] for x in о["знахідки"] if x.get("регістр") == "гейт" or x.get("без_замків")]
            підсумок["образів"] += 1; підсумок["gate_до"] += з["рівень"] == "gate"; підсумок["gate_після"] += після == "gate"
            print(os.path.basename(шлях)[:8], з["рівень"], "→", після, "блокерів", len(s["blockers"]), "→", len(блок),
                  "K-SHO-01 знято", len(s["findings"]) - len(о["знахідки"]), "лишилось", лишились, "нема", sorted({x["слот"] for x in нема})[:6])
            if "вхід_прогону" in д["спільне"]:           # повний суд на записаних речах (як класи_б4 з дослідження)
                вх = dict(д["спільне"]["вхід_прогону"], речі=е["речі"]["речі"], пікселі={}, сценарій_оцінки=е.get("сценарій_екрана") or {})
                вх.pop("каталог", None); О._виміри = lambda *а, **к: copy.deepcopy(з["речі"])
                п = О.суд(вх)
                print("   повний суд: блокерів", len(п["суд"]["blockers"]), "рівень", п["рівень"], "не_на_фото", len(п["не_на_фото"]))
print(підсумок)
