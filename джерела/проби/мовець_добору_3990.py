"""Рядок 3990: хто говорить у рядку добору. ДО — записаний вхід і відповідь шару (ЖИВІ-15 №11, `seed3_31`): чи стоїть
у промпті рядок про мовця добору і скільки рядків видів добору відповідь почала з «я обрала/замінила/додала». ПІСЛЯ —
той самий вхід, перебудований `промпт_повідомлень` (без моделі: відповідь дає живий прогін). Запуск із джерела/:
git -c core.quotepath=off show 'origin/claude/zhyvi-15:аудит/живі_15/А/11_ж2_новорічна_мороз/VIDPOVIDI/seed3_31_мовний_шар.txt' > /tmp/s.txt
python3 проби/мовець_добору_3990.py /tmp/s.txt"""
import os, re, sys, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import мовний_шар as МШ
СТАРІ = {"card_added_by_code": "card_added_by_selection", "item_added_by_code": "item_added_by_selection",
         "code_swapped_item_from_stylist_look": "selection_swapped_item_from_stylist_look"}
т = open(sys.argv[1], encoding="utf-8").read()
запит, відповідь = т.split("── ВІДПОВІДЬ", 1)
сирий = запит.split("\nПОВІДОМЛЕННЯ:\n", 1)[1].strip()
for с, н in СТАРІ.items():
    сирий = re.sub(r"\b%s\b" % с, н, сирий)
розмітка = json.loads(сирий[: сирий.rindex("]") + 1])
тексти = json.loads(відповідь[відповідь.index("{"): відповідь.rindex("}") + 1])
добору = [str(р["н"]) for р in розмітка if р["вид"] in МШ.ВИДИ_ДОБОРУ]
я = [н for н in добору if re.match(r"\s*Я (обрала|замінила|додала)", тексти.get(н, ""))]
після = МШ.промпт_повідомлень(розмітка)
print("рядків видів добору: %d · відповідь ДО з «я обрала/замінила/додала»: %d (%s)" % (len(добору), len(я), ", ".join(я)))
print("рядок про мовця добору в промпті: ДО %d · ПІСЛЯ %d" % (int("добір, а не стилістка: підмет" in запит),
                                                              int(МШ.РЯДОК_МОВЕЦЬ_ДОБОРУ in після)))
print("промпт без видів добору рядка не несе:",
      МШ.РЯДОК_МОВЕЦЬ_ДОБОРУ not in МШ.промпт_повідомлень([р for р in розмітка if р["вид"] not in МШ.ВИДИ_ДОБОРУ]))
