"""Ф2/2.5: друкує договір кодів і рішення на каталозі біля погодних меж; не гейт.
Виклик: python3 проби/wea_канон.py <джерела> <каталог.json>.
"""
import collections, hashlib, json, pathlib, sys
sys.path.insert(0, str(pathlib.Path(sys.argv[1]).resolve()))
import сценарій as С, аксесуари_погода as А, пакет_моделі as П, outfit as О, суд_погода as СП, profile as Ф
друк = lambda v: print(json.dumps(v, ensure_ascii=False, sort_keys=True))
кат = json.loads(pathlib.Path(sys.argv[2]).read_text())
друк({"каталог": len(кат), "договір": Ф.ПОГОДА_КОНТРАКТ["опади"]["значення"]})
for к in ("none", "possible_rain", "rain", "sleet", "downpour", "snow", "ні", "нема", "немає", "так", "невідомо"):
    друк({"код": к, "канон": [С.канон_опади(к, т) for т in С.СМУГИ_ПОГОДИ]})
for т in С.СМУГИ_ПОГОДИ:
    рішення, лічба = [], collections.Counter()
    for р in кат:
        відсів = П.жорстке_відсічення(р, смуга_погоди=т)
        знахідки = А.сезон_і_погода([р], смуга_погоди=т, опади="дощ")
        з = [(з.get("правило"), з.get("регістр"), з.get("сила_нп")) for з in знахідки]
        рішення.append([р["id"], відсів, з]); лічба.update([відсів] if відсів else [])
        лічба.update(з[0] for з in з)
    друк({"смуга_погоди": т, "рішення_sha256": hashlib.sha256(json.dumps(рішення, ensure_ascii=False, sort_keys=True).encode()).hexdigest(),
          "лічба": dict(лічба), "сіль_сніг": С.сіль_на_дорозі(None, т, "сніг")[0],
          "смуга_ніг": А.смуга_ніг(т), "мапа": О.ТЕМП_МАПА[т]})
річ = dict(id="проба", слот="сукня", hex="#334455", тип="сукня", крій="кльош", матеріал="шифон", волокно="шовк", назва="")
for в in (None, 8, "calm", "moderate", "strong"):      # число м/с — не смуга: правила мовчать
    зн = СП.погода(О.елементи([річ], стан="надворі"), смуга_погоди='cool', смуга_вітру=в, стан="надворі", речі=[річ])
    друк({"смуга_вітру": в, "wind_band": С.день_кодами(dict(смуга_вітру=в)).get("wind_band"),
          "поділ": sum("кльош" in з["суть"] for з in зн), "непогода": С.сильна_непогода("дощ", "cool", None, в)})
