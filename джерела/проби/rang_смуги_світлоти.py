# -*- coding: utf-8 -*-
"""C: ряд «рекомендовані» — не смуга світлоти. У кожній смузі хроми кожна смуга
світлоти, де є клітинка над підлогою (0.5), представлена своєю найкращою; смуги
без жодної над підлогою — названі жінці словами (ширина_ряду.словами, K-CLR-02).
Друкує на трьох профілях: смуги над підлогою / представлені, std L*, слова."""
import sys, os, json, statistics as st
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import colorspace as cs, bridge as B, bases as ОС
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
ПРОФІЛІ = [("1 середня нейтральна", вх["шкіра"], вх["волосся"][0], вх["очі"]),
           ("2 світла холодна", "#eec2b0", "#e8d5b0", "#8a9bb0"),
           ("3 смаглява тепла", "#96632f", "#3a2a1a", "#4a3222")]
св = lambda x: int(x["ключ"].split("·")[-2]); см = lambda x: x["ключ"].split("·")[-1]
пропущено = 0
for назва, шк, вл, оч in ПРОФІЛІ:
    F = cs.features(cs.hx(шк), cs.hx(вл), cs.hx(оч))
    о = B._основи(F, intent="conventional")
    рек, усі = о["рекомендовані"], о["рекомендовані"] + о["інші"]
    ключі = {x["ключ"] for x in рек}
    print("\n=== %s: рекомендовано %d, ліміт контрасту %s L* ===" % (назва, len(рек), о["ширина_ряду"]["ліміт_контрасту"]))
    for смуга in ("приглушені", "середні", "насичені"):
        for рід, умова in (("нейтралі", lambda x: x["осі"]["Cstar"] < ОС.АХРОМАТИЧНА_МЕЖА),
                           ("кольори", lambda x: x["осі"]["Cstar"] >= ОС.АХРОМАТИЧНА_МЕЖА)):
            кл = [x for x in усі if см(x) == смуга and умова(x)]
            над = sorted({св(x) for x in кл if x["бал"] >= ОС.ПІДЛОГА_РЕКОМЕНДАЦІЇ})
            є = sorted({св(x) for x in кл if x["ключ"] in ключі})
            пропущено += len(set(над) - set(є))
            print("  %-10s %-8s смуги L* над підлогою %-18s представлені %s" % (смуга, рід, над, є))
    print("  std L*: рекомендовані=%.1f, уся ґратка=%.1f (до правки: 6.4 / 0.1 / 12.5)"
          % (st.pstdev([x["осі"]["L"] for x in рек]), st.pstdev([x["осі"]["L"] for x in усі])))
    print("  жінці: %s" % о["ширина_ряду"].get("словами", "ряд не вузький — усі смуги світлоти є"))
print("\nсмуг світлоти над підлогою без представника: %d" % пропущено)
