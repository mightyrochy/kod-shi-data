"""ХІД-ФОРМИ (рядки 6067, 6068, 6073; мірила 5273, 6074): записані ходи розмови живого-14 (`claude/zhyvi-pachka-14`) і
перші ходи Ж20–22 тим кодом, що в теці аргументу (типово `.`): `прийняти_розмову` → `паспорт_з_шару`, без моделі.
Друкує: хід не прочитано (причина), бульбашку й мету паспорта на сценах 06, 11, 15, 22, 24; лічби — сцени 22–26 з
`belly` у паспорті, бульбашки 12–16 / 17–21 з записаною метою (слово мірила — живіт / вищ), бульбашки з «ви» (01–26)
і Ж20–22 з «Розкажи» (рядок 4361). Лічба словами — мірило проби, не код продукту.
Запуск: cd джерела && python3 проби/хід_форми_6067.py [тека джерел іншої збірки]"""
import json, re, subprocess, sys
sys.path.insert(0, sys.argv[1] if len(sys.argv) > 1 else "."); import мовний_шар as М
git = lambda *а: subprocess.run(["git", "-c", "core.quotepath=false", *а], capture_output=True, text=True).stdout
ВИ = re.compile(r"(?<![а-яіїєґ'’])(ви|вас|вам|ваш\w*|хочете)(?![а-яіїєґ'’])", re.I)
def ходи(гілка, тека, лише_перші=False):
    git("fetch", "-q", "origin", гілка)
    for ф in git("ls-tree", "-r", "--full-tree", "--name-only", "origin/" + гілка, тека).splitlines():
        if ф.endswith("_мовний_шар_хід_розмови.txt") and (not лише_перші or "_01_" in ф):
            с = git("show", "origin/%s:%s" % (гілка, ф)); вх = json.loads(с.split("\n", 1)[1].split("\n── ВІДПОВІДЬ")[0])
            р = М.прийняти_розмову(с.split("── ВІДПОВІДЬ", 1)[1].split("──", 1)[1])
            ш = {} if р.get("причина") else М.паспорт_з_шару(р["внутрішня"], {}, слова_ходу=[вх["her_new_message"]],
                                                             частини=р["частини"])
            yield ф.split("/")[-3][:2], ф.split("/")[-1][:8], р.get("причина"), ш.get("текст") or "", ш.get("паспорт") or {}
лік = dict(не_прочитано=0, ходів=0, бел=set(), мета_живіт=set(), мета_вищ=set(), ви=0, розкажи=0)
for сц, сід, чому, текст, п in ходи("claude/zhyvi-pachka-14", "аудит/живі_пачка_14"):
    лік["ходів"] += 1; лік["не_прочитано"] += bool(чому)
    if сц in ("06", "11", "15", "22", "24"):
        print(сц, сід, "·", чому or текст, "·", {к: п.get(к) for к in ("намір", "мета", "мета_зони") if п.get(к)})
    if "живіт" in (п.get("мета_зони") or ()) and "22" <= сц <= "26": лік["бел"].add(сц)
    if "12" <= сц <= "16" and re.search("живіт|живот", текст): лік["мета_живіт"].add(сц)
    if "17" <= сц <= "21" and "вищ" in текст: лік["мета_вищ"].add(сц)
    лік["ви"] += bool(сц <= "26" and ВИ.search(текст))
for ж in ("20", "21", "22"):
    for сц, сід, чому, текст, п in ходи("claude/zhyvi-" + ж, "аудит/живі_%s/А" % ж, True):
        лік["розкажи"] += "Розкажи" in текст
print("ходів %(ходів)s, не прочитано %(не_прочитано)s · belly у паспорті сцен 22–26: %(бел_)s · мета в бульбашці 12–16: "
      "%(жив)s з 5, 17–21: %(вищ)s з 5 · бульбашок з «ви» 01–26: %(ви)s · Ж20–22 «Розкажи» в бульбашці: %(розкажи)s"
      % dict(лік, бел_=len(лік["бел"]), жив=len(лік["мета_живіт"]), вищ=len(лік["мета_вищ"])))
