"""Рядок 3160: хід стилістки послаблює лише знахідку, яку назвав кодом. Живий 12 А/08, рука 2 (картка 4): вибір
прийняв регістровий гейт з-о5-9 (K-REG-01) над усіма 7 речами. ДО — живий запис; ПІСЛЯ — той самий суд картки
(×0.6 знято) і той самий хід через `_застосувати_свідомі` з кодом знахідки."""
import json, os, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import розбір_відповідей as РВ
шлях = "origin/claude/zhyvi-12:аудит/живі_12/А/08_ж7_мороз_без_відкритого/вердикти.txt"
try:
    о = json.loads(subprocess.run(["git", "show", шлях], capture_output=True, text=True, check=True).stdout)
except (subprocess.CalledProcessError, ValueError) as e:
    sys.exit("нема гілки живих 12 (git fetch origin claude/zhyvi-12): %s" % e)
в = [x for x in о["прогони"][0]["вердикти"] if x.get("рука") == "2"][0]
межа = (о["спільне"].get("паспорт") or {}).get("відкриті_зони")
до = [z for z in в["знахідки_коду"] if z.get("свідомий")]
print("ДО     послаблено %d із %d: %s" % (len(до), len(в["знахідки_коду"]), ", ".join(z["правило"] for z in до)))
зн = []                       # суд картки без оголошень: ×0.6 знято з позначених
for z in в["знахідки_коду"]:
    z = dict(z, речі=z.get("речі") or [], сила_нп=round(z["сила_нп"] / РВ.СВІДОМИЙ_МНОЖНИК, 2) if z.get("свідомий") else z["сила_нп"])
    z.pop("свідомий", None)
    if z["правило"] == "K-KOH-10" and межа:   # ПІСЛЯ цю позначку ставить суд (open_zones паспорта)
        z["межа_паспорта"] = True
    зн.append(z)
ід = в["свідомі_ід"].split("+")
хід = dict(ід=ід[0], ід_речей=ід, текст=в["свідомі"][:60], знахідка="з-о5-9", правило="K-REG-01")
після, звіт = РВ._застосувати_свідомі([dict(z) for z in зн], [хід], [dict(id=і) for і in ід])
посл = [z["правило"] for z in після if z.get("свідомий")]
print("ПІСЛЯ  послаблено %d із %d: %s" % (len(посл), len(після), ", ".join(посл) or "—"))
к10 = [(a["сила_нп"], b["сила_нп"]) for a, b in zip(в["знахідки_коду"], після) if a["правило"] == "K-KOH-10"]
print("K-KOH-10 (open_zones=%s): ДО %.2f → ПІСЛЯ %.2f; K-REG-01 у суді картки: %s" % (
    межа, к10[0][0], к10[0][1], any(z["правило"] == "K-REG-01" for z in зн)))
