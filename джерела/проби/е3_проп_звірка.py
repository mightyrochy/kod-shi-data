"""Звірити знахідки двох знімків (е3_проп_знімок.py); друк таблиць сирих і ефективних змін ваги."""
import collections, gzip, json, sys


def main():
    """Склад (поля 0–6) тотожний; змінені сира й ефективна вага — таблицями за правилом, силою, ДО, ПІСЛЯ."""
    def читати(шлях):
        with gzip.open(шлях, 'rt', encoding='utf-8') as ф:
            return json.load(ф)
    до, після = map(читати, sys.argv[1:3])
    assert len(до) == len(після), (len(до), len(після))
    сирі, ефективні, підлога = collections.Counter(), collections.Counter(), collections.Counter()
    for д, п in zip(до, після):
        assert д[:7] == п[:7], (д[:7], п[:7])
        групується = 'свідомий' if д[1] == 'застосувати_свідомі' else ''
        if д[7] != п[7]:
            сирі[д[2], д[5], д[7], п[7]] += 1
        if д[8] != п[8]:
            ефективні[д[2], д[5], д[8], п[8]] += 1
        if д[9] != п[9]:
            підлога[д[2], д[9], п[9]] += 1
    print('знахідок', len(до), '— склад, сила, блокує тотожні; сирих змін', sum(сирі.values()),
          'ефективних', sum(ефективні.values()), 'зміна позначки підлоги', sum(підлога.values()))
    print('| правило | сила | сира ДО | сира ПІСЛЯ | кількість |\n|---|---|---|---|---|')
    for (пр, с, а, б), н in sorted(сирі.items(), key=str)[:60]:
        print('| %s | %s | %s | %s | %d |' % (пр, с, а, б, н))
    print('| правило | сила | ефективна ДО | ефективна ПІСЛЯ | кількість |\n|---|---|---|---|---|')
    for (пр, с, а, б), н in sorted(ефективні.items(), key=str)[:80]:
        print('| %s | %s | %s | %s | %d |' % (пр, с, а, б, н))
    print('підлога:', sorted(підлога.items(), key=str)[:20])


if __name__ == '__main__':
    main()
