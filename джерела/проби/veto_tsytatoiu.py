"""Вето тримається ЦИТАТОЮ моделі, а не словником заперечень у коді. Словник щоразу доганяв нову фразу
(«смужку? ні», «ні в якому разі»). Тепер модель дає слово з ДОСЛІВНОЮ цитатою, а код звіряє лише
механіку. Із теки `джерела`: PYTHONPATH=. python3 проби/veto_tsytatoiu.py"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); import паспорт_нагоди as ПН
ОСІ, ІР = ("типи", "тканини", "принти", "кольори", "зони"), "Можна яскравий верх — куртку чи жакет, не темного кольору"
КУРТКИ = "не ношу куртки, краще пальто чи тренч"
ВИПАДКИ = [           # (слова жінки, вісь, слово моделі, цитата або "", чи МАЄ бути твердим)
    # РЯДОК 156: збережена відповідь ТОГО прогону цитат не має — її тримає запасний словник, як доти.
    # За НОВИМ промптом куртка й жакет ідуть у «бажання», а вето лишається на кольорі, і тверде воно.
    (ІР, "типи", "куртка", "", False), (ІР, "типи", "блейзер", "", False),
    (ІР, "кольори", "темні кольори", "не темного кольору", True),
    # ФРАЗИ ТЕСТУВАЛЬНИЦЬ, де словник мовчав; «смугасте» — її форма проти канонічної «смужка»
    ("смужку? ні, клітинку хочу", "принти", "смужка", "смужку? ні", True),
    ("смужку? ні, клітинку хочу", "принти", "клітинка", "", False),
    ("не хочу темні кольори", "кольори", "темні кольори", "не хочу темні кольори", True),
    ("смугасте ні в якому разі", "принти", "смужка", "смугасте ні в якому разі", True),
    ("ніяких підборів", "типи", "підбори", "ніяких підборів", True),
    (КУРТКИ, "типи", "куртка", "не ношу куртки", True), (КУРТКИ, "типи", "пальто", "", False),
    ("люблю смужку", "принти", "смужка", "смужку не ношу", False),          # брехлива цитата
    ("не ношу шкіру, смужку люблю", "принти", "смужка", "не ношу шкіру", False),  # цитата не про ту річ
]


def тверде(слова, вісь, слово, цитата):
    """Чи тримає код це слово твердою межею при цих словах і цій цитаті."""
    п = dict(слова=слова, вето={к: ([слово] if к == вісь else []) for к in ОСІ})
    if цитата:
        п["цитати_слів"] = {слово.lower(): цитата}
    return слово in (ПН.вето_тверде(п).get(вісь) or [])


впало = 0
for слова, вісь, слово, цитата, треба in ВИПАДКИ:
    факт = тверде(слова, вісь, слово, цитата); впало += факт != треба
    print("%s %-42s %-7s «%-14s» цитата «%s» → тверде %s"
          % ("✔" if факт == треба else "✗", слова[:42], вісь, слово, цитата or "—", факт))
print("ФАКТ: розбіжностей із очікуваним %d із %d" % (впало, len(ВИПАДКИ)))
assert not впало
