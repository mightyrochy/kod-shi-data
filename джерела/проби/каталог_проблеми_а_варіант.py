# -*- coding: utf-8 -*-
"""Реєстр А (рядок 5630), клас А3: на картці кадр іншого кольору чи варіанта. Друкує стани
`фід_кадр_колір.рішення` на каталозі («свій» — кадр жнив у кольорі речі; «свій_кадр» — першим став
інший кадр галереї; «інший_колір» — кадру свого кольору код не знайшов, картка несе заяву),
скільки «інший_колір» мають виміряну галерею в `каталог_кадри.json.gz` і перші крамниці.
Запуск: cd джерела && python3 проби/каталог_проблеми_а_варіант.py"""
import collections, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed as Ф, фід_фото as ФФ, фід_кадр_колір as ФКК
from фід_збагачення import _збагачення_придатне
оф = Ф.читати_yml(Ф.каталог_на_диску("каталог_повний.xml"))[0]
зб, сп = Ф.читати_збагачення(), ФФ._спільні_фото(оф)
к, кадри = ФКК.контекст(оф, зб, сп), ФКК.читати_кадри()
стани, крамниці, з_галереєю = collections.Counter(), collections.Counter(), 0
for o in оф:
    з = зб.get(o["id"])
    ок = _збагачення_придатне(з) and not ФФ.чужий_кадр(з.get("фото"), сп.get(o.get("магазин")) or {})
    с = ФКК.рішення(o, з if ок else None, к).get("стан") or "немає"   # як картка: `міст_опис._фото_речі`
    стани[с] += 1
    if с == "інший_колір":
        крамниці[o.get("магазин")] += 1; з_галереєю += bool(кадри.get(o["id"]))
print("стани кадру картки (непридатне чи чуже збагачення — без кадру жнив):", dict(стани.most_common()))
print("інший_колір: %d, з них із виміряною галереєю %d, без неї %d" % (стани["інший_колір"], з_галереєю, стани["інший_колір"] - з_галереєю))
print("  по крамницях:", крамниці.most_common(10))
print("записів у каталог_кадри: %d" % len(кадри))
