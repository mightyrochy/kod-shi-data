"""Кнопка «Скопіювати/Зберегти всі вердикти» щоразу віддає ВЕСЬ журнал телефона.
Друкує, скільки вердиктів другого файла власника вже були в першому, скільки
це коштує символів, і що вибору прогонів/днів та позначки «вже вивантажено»
нема: обидва шляхи беруть `усіВердикти()` без фільтра.
"""
import json
import pathlib

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
ПОКАЗ = (КОРІНЬ / "джерела" / "показ.html").read_text(encoding="utf-8")


def ключі(д):
    о = {}
    for п in д["прогони"]:
        for в in п["вердикти"]:
            о[(п["прогін"], в.get("рука"), в.get("час"))] = len(json.dumps(в, ensure_ascii=False))
    return о


тека = КОРІНЬ / "аудит" / "тести" / "власник_2026-09-25"
перший = ключі(json.loads((тека / "verdykty-0phxvk-2026-09-25-1953.json").read_text(encoding="utf-8")))
другий = ключі(json.loads((тека / "verdykty-0phxvk-2026-09-25-2012.json").read_text(encoding="utf-8")))
спільні = set(перший) & set(другий)
print("файл 19:53 —", len(перший), "вердиктів · файл 20:12 —", len(другий), "вердиктів")
print("у другому файлі ПОВТОРЕНО з першого:", len(спільні), "з", len(другий),
      "·", sum(другий[к] for к in спільні), "символів з", sum(другий.values()),
      "(%.0f %%)" % (100 * sum(другий[к] for к in спільні) / sum(другий.values())))
for к in sorted(спільні):
    print("   повтор:", к[0][:44], "· рука", к[1], "·", к[2][:19])
for к in sorted(set(другий) - спільні):
    print("   новий :", к[0][:44], "· рука", к[1], "·", к[2][:19])

print("у показі:")
рядки = ПОКАЗ.splitlines()
for н, р in enumerate(рядки, 1):
    if "усіВердикти()" in р:
        print("   ", н, р.strip()[:110])
print("    поле «вивантажено» (час експорту в шапці файла):", ПОКАЗ.count("вивантажено"),
      "· жодного поля на САМОМУ записі:", ПОКАЗ.count("запис.вивантажено"))
