def всередині(x, y, п): return sum((ay > y) != (by > y) and x < (bx - ax) * (y - ay) / (by - ay) + ax for (ax, ay), (bx, by) in zip(п, п[1:] + п[:1])) % 2
def кадр(фото, р):
    W, H, тло, фіг = фото
    л, в, п, н = р["ліво"], р["верх"], р["право"], р["низ"]; dx, dy = (п - л) * .12, (н - в) * .12
    л2, в2, п2, н2 = max(0, л - dx), max(0, в - dy), min(1000, п + dx), min(1000, н + dy)
    x0, x1, y0, y1 = [round(a / 1000 * s) for a, s in ((л2, W), (п2, W), (в2, H), (н2, H))]
    к = min(1, 128 / max(x1 - x0, y1 - y0, 1)); w, h = max(1, round((x1 - x0) * к)), max(1, round((y1 - y0) * к))
    піксель = lambda x, y: next((к_ for к_, ф in reversed(фіг) if всередині(x + .5, y + .5, ф)), тло)
    сирі = bytes(b for j in range(h) for i in range(w) for b in піксель(x0 + i / к, y0 + j / к))
    я = dict(ліво=(л - л2) / (п2 - л2), верх=(в - в2) / (н2 - в2), право=(п - л2) / (п2 - л2), низ=(н - в2) / (н2 - в2))
    return dict(дані=base64.urlsafe_b64encode(сирі).decode(), ширина=w, висота=h, ядро={к_: round(v * 1000) for к_, v in я.items()})
