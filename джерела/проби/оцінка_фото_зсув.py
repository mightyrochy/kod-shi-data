        print("  %-5s %-11s слово %-10s ДО %-9s → ПІСЛЯ %-5s %-9s color_named=%s" % (х["ід"], х.get("слот"), х.get("колір"),
              д.get("слово") or "—", п_["ід"], (п_.get("вимір") or {}).get("слово") or "—", м.get("color_named")))
