"""5194: 20 речей, чий щабель ошатності змінився (ДО — зріз `пул_5194_до.json.gz`, ПІСЛЯ — зараз), для огляду очима:
назва, опис з фото (`каталог_збагачення`), тип, бал фото, поля, які зсували щабель ДО (волокно, матеріал).
Сід 5194, без вибору «зручних». Запуск: cd джерела && python3 проби/ошатність_5194_вибірка.py"""
import gzip, json, os, random, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as FK, outfit as O, формальність as ФМ
до = json.load(gzip.open("дані_5191_5194/пул_5194_до.json.gz", "rt", encoding="utf-8"))["щаблі"]
зб = json.load(gzip.open("каталог_збагачення.json.gz", "rt", encoding="utf-8"))
кат = {r["id"]: r for r in FK._прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"]}
к = ("тип", "тип_модифікатор", "формальність_фото", "текстура", "матеріал", "волокно")
після = {і: list(ФМ.інтервал_формальності(dict({x: r.get(x) for x in к}, річ=і, формальність=r.get("формальність") or O.ТИП_ФОРМАЛЬНІСТЬ.get(r.get("тип"))))) for і, r in кат.items()}
змінені = sorted(і for і in після if після[і] != до.get(і))
print("змінилось %d із %d; вибірка 20 (сід 5194):" % (len(змінені), len(після)))
for і in random.Random(5194).sample(змінені, 20):
    r = кат[і]
    print("%s [%s] %s · тип %s · бал фото %s · волокно %s · матеріал %s · текстура %s\n    ДО %s → ПІСЛЯ %s\n    опис: %s" % (
        і[:22], r.get("слот"), r.get("назва", "")[:60], r.get("тип"), r.get("формальність_фото"), r.get("волокно"),
        str(r.get("матеріал"))[:30], r.get("текстура"), до.get(і), після[і], str((зб.get(і) or {}).get("опис") or "—")[:130]))
