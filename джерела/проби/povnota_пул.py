# -*- coding: utf-8 -*-
"""ПРОБА: скільки речей обовʼязкових слотів і «третьої речі» доходить до моделі.

Сценарій власниці (побачення, ресторан, 19:00, 20 °C, сукня дозволена) на
`каталог_повний.xml`, три сіди. Друкує лічбу в КАТАЛОЗІ й у ПУЛІ пакета
(після семплера й бюджету): якщо слот у каталозі непорожній, а в пулі його
менше за десяток, модель не має чим закрити блокер «нема сумки»."""
import json, os, sys
_ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _ТУТ); os.chdir(_ТУТ)
import bridge as B, feed as Ф

ПРИКРАСИ = ("сережки", "кольє", "намисто", "браслет", "каблучка", "брошка", "прикраси")
СЛОТИ = ("сумка", "верхній_шар", "пояс", "шарф", "головний_убір") + ПРИКРАСИ
уКат = {с: len(v) for с, v in Ф.розкласти_по_слотах(Ф.читати_yml("каталог_повний.xml")[0])[0].items()}
print("каталог: " + ", ".join("%s %d" % (с, уКат.get(с, 0)) for с in СЛОТИ))
для_рядка = lambda п: ", ".join("%s %d" % (с, len(п.get(с) or [])) for с in СЛОТИ)
for сід in (4242, 17, 101):
    вх = dict(json.load(open("стенд_вх.json")), каталог="каталог_повний.xml", сід=сід,
              сценарій=dict(нагода="побачення", місце="ресторан", година=19, темп_c=20),
              випадок="побачення, ресторан, 19:00, 20 °C")
    з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    пул = json.loads(з["руки"]["1"])["пул"]
    прик = sum(len(пул.get(с) or []) for с in ПРИКРАСИ)
    print("сід %-5d пул %4d речей | %s | прикрас разом %d"
          % (сід, з.get("пул_речей") or 0, для_рядка(пул), прик))
