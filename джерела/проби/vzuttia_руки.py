# -*- coding: utf-8 -*-
"""ОДНІ Й ТІ САМІ ТУФЛІ В ДВОХ КАРТКАХ ОДНОГО ПРОГОНУ — ДЕ ЦЕ РОБИТЬСЯ.

Власник побачив на опублікованому продукті (18.09.2026): з чотирьох карток дві —
руки 1 і 2, обидві з крамницями й цінами — стояли на ТІЙ САМІЙ парі, при сотнях
пар у каталозі. Проба міряє два яруси цього:
  1) ПОРЯДОК. Обидві руки дістають ОДИН сід прогону (`bridge._пакет_каталогу`
     ставить `сцен["сід"] = вх["сід"]`), а нічию за колірною відстанню розв'язує
     `composer._перемішати(підходящі, сід, слот)`. Отже пул у слоті «взуття»
     впорядкований для рук 1 і 2 однаково, і модель в обох бере голову списку.
  2) НАСЛІДОК. Десять образів моделі на ОДНІЙ парі: чи назве `вердикт.набір`
     знахідку з регістром і `сила_нп`, чи скаже «усі 10 образів різні».
Запуск: PYTHONPATH=. python3 проби/vzuttia_руки.py   (потрібен каталог_повний.xml)
"""
import sys, json, pathlib
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import bridge as B, pipeline as PL

_ярус, _ор = [], PL.відсікти_пул
def _міряти(канд, *a, **k):                       # ярус «після відсічень» інакше не видно
    r = _ор(канд, *a, **k)
    _ярус.append((len((канд or {}).get("взуття") or []), len((r[0] or {}).get("взуття") or [])))
    return r
PL.відсікти_пул = _міряти

вх = dict(json.load(open(_К / "стенд_вх.json", encoding="utf-8")),
          каталог=str(_К / "каталог_повний.xml"), гілка=0, варіантів=10,
          сценарій=dict(нагода="побачення", місце="ресторан", година=19, темп_c=20,
                        дрес_код="cocktail"),
          випадок="побачення, ресторан, 19:00, 20 °C")
останній = None
for сід in (4242, 17, 101):
    del _ярус[:]
    r = json.loads(B.виклик("запити", json.dumps(dict(вх, сід=сід), ensure_ascii=False)))
    а = [x["id"] for x in (r["кандидати"].get("взуття") or [])]
    б = [x["id"] for x in (r["кандидати_донора"].get("взуття") or [])]
    кат = [x for x in B.каталог_останнього_пакета() if x.get("слот") == "взуття"]
    (в1, п1), (в2, п2) = _ярус[0], _ярус[1]
    print("сід %-5d ярус взуття: каталог %d (%d моделей) → вікна композитора (стеля "
          "K_НА_СЛОТ) %d/%d → відсічення %d/%d → семплер і бюджет %d/%d  (рука1/рука2)"
          % (сід, len(кат), len({x.get("group_id") or x.get("id") for x in кат}),
             в1, в2, п1, п2, len(а), len(б)))
    print("   різних моделей у пакеті: %d / %d · перетин топ-10 рук 1∩2: %d із 10 (%d %%) · "
          "перетин усього слота: %d" % (len(set(а)), len(set(б)),
          len(set(а[:10]) & set(б[:10])), 10 * len(set(а[:10]) & set(б[:10])), len(set(а) & set(б))))
    print("   рука 1 перші 10: %s" % ", ".join(x.split("@")[0] for x in а[:10]))
    print("   рука 2 перші 10: %s" % ", ".join(x.split("@")[0] for x in б[:10]))
    останній = (сід, r)
    assert len(set(а[:10]) & set(б[:10])) < 10, "руки 1 і 2 стоять у слоті в тому самому порядку"

сід, r = останній
к = r["кандидати"]
ід = lambda с, n: [x["id"] for x in (к.get(с) or [])][:n]
пара, сукні, сумки = ід("взуття", 1)[0], ід("сукня", 10), ід("сумка", 10)
прикр = ід("прикраси", 10) or ід("сережки", 10)
набори = [[сукні[i], пара, сумки[i % len(сумки)], прикр[i % len(прикр)]]
          for i in range(min(10, len(сукні)))]
н = (json.loads(B.виклик("від_моделі", json.dumps(dict(вх, сід=сід, ід=набори),
                                                  ensure_ascii=False))).get("вердикт") or {}).get("набір") or {}
зн = [z for z in (н.get("знахідки") or []) if z.get("правило") == "K-VAR-01"]
print("10 образів на ОДНІЙ парі (%s): різноманітність.ок=%s · «%s»"
      % (пара.split("@")[0], (н.get("різноманітність") or {}).get("ок"),
         ((н.get("різноманітність") or {}).get("чому") or "")[:90]))
print("   K-VAR-01: %s" % ("НЕМА — наслідку нуль" if not зн else
      "; ".join("%s · регістр %s · сила_нп %s" % (z["суть"][:70], z.get("регістр"),
                                                  z.get("сила_нп")) for z in зн)))
