# -*- coding: utf-8 -*-
"""Рядок 179: семплер брав ті самі голови на кожному сіді. Сорт страт за розміром
скасовував перемішування (стабільний сорт лишає його лише серед рівних), тож у
тісну квоту потрапляли перші `квота` страт — ті самі щоразу; а в страті `_розкидом` ставив
першими min, max і медіану ціни поза сідом (прибрано В-1 26.09: у групі — рівний шанс).

Друкує на брифовому пулі: покриття п'яти сідів при K, слоти без вибору (менш ніж
`МІН_ОБОВЯЗКОВОГО` речей при непорожньому пулі), детермінізм складу на одному
сіді й рівний шанс у групі. Підлога слота лишається 20 (рядок 172).
Запуск із теки `джерела`: python3 проби/sempler_start_179.py"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import feed as Ф, семплер as С
офери, _ = Ф.читати_yml(Ф.каталог_на_диску("каталог_brief.xml"))
по_слотах, _ = Ф.розкласти_по_слотах(офери)
пул = {с: [dict(id="%s@%s" % (o["id"], o.get("магазин") or "?"), ціна=o.get("ціна") or 0.0,
                гілка="ядро", тип=Ф.тип_речі(o, с), зона=(o.get("колір_назва") or None))
           for o in речі] for с, речі in по_слотах.items()}
усього, біди = sum(len(v) for v in пул.values()), 0
for K, підлога_гейта in ((129, 0.65), (180, None), (220, None)):
    вибірки = [С.вибрати(пул, K, сід=с) for с in (1, 2, 3, 4, 5)]
    союз = set().union(*[{r["id"] for сл in в.values() for r in сл} for в in вибірки])
    без = {с: len(вибірки[0].get(с) or []) for с in пул
           if пул[с] and len(вибірки[0].get(с) or []) < min(С.МІН_ОБОВЯЗКОВОГО, len(пул[с]))}
    частка = len(союз) / усього
    біди += len(без) + (1 if (підлога_гейта and частка < підлога_гейта) else 0)
    print("K=%3d · покриття п'яти сідів %3d із %d = %.1f %%%s · слотів без вибору %d%s"
          % (K, len(союз), усього, 100.0 * частка,
             (" (підлога гейта %.0f %%)" % (100 * підлога_гейта)) if підлога_гейта else "",
             len(без), (" ← " + str(без)) if без else ""))
_один = lambda: [r["id"] for сл in С.вибрати(пул, 129, сід=3).values() for r in сл]
_детерм = _один() == _один()
_одна = {"верх": [dict(id="ж-%04d@shop" % i, ціна=100.0 + 7 * i, гілка="ядро", тип="блуза", зона="z1")
                  for i in range(40)]}
_л = __import__("collections").Counter(r["id"] for с in range(1, 401) for r in С.вибрати(_одна, 3, сід=с)["верх"])
_рівно = len(_л) == 40 and max(_л.values()) < 3 * min(_л.values())   # 400 сідів × 3 із 40: очікувано 30
біди += (0 if _детерм else 1) + (0 if _рівно else 1)
print("склад на одному сіді детермінований: %s · рівний шанс у групі (400 сідів, 3 із 40): кожна річ "
      "%d–%d разів із очікуваних 30 → %s" % (_детерм, min(_л.values()), max(_л.values()), _рівно))
print("ВИСНОВОК: порушень приймання — %d" % біди)
sys.exit(1 if біди else 0)