# -*- coding: utf-8 -*-
"""K-MUA-01 (велика річ не повторює колір макіяжу) — анти-правило вимикав гейт,
який стереже зовсім інше.

ДО ПРАВКИ: `_кулі_слотів` першим рядком питала `тон_від_рис["придатно"]` — тобто
надійність ТОНУ З ФОТО (0.35 проти порога 0.5 на неконтрольованому знімку). На
живому шляху це False ЗАВЖДИ, отже куля виключення не будувалась ЖОДНОГО разу.
ЧОМУ ЦЕ ПОМИЛКА КАТЕГОРІЇ: гейт K-PC-05 стереже ДУГИ, пораховані з абсолютного
тону риси на фото, — вони не переживають баланс білого. Куля дуг не використовує:
у ній рівно дві величини — hex, який НАЗВАЛА ЖІНКА (камера тут ні до чого), і
поріг ΔE00 5.0.
ПІСЛЯ: куля будується. Проба друкує вимір до/після і НАЗИВАЄ МЕЖУ — ту, яка є
СЬОГОДНІ, а не ту, яка була: колір великої речі приходить або ТОЧКОЮ з фото
(`джерело_кольору = фото`), або ЗОНОЮ зі слова назви (`назва_вікно`). Куля ріже
точку точно; зону вона ріже в центрі, тож річ, чия зона лише перетинає кулю,
законно лишається — і саме на цю підмножину межа й поширюється.
17.09.2026, ОПИС ІЗ ФОТО: доти проба стверджувала «УСІ великі речі несуть зону»
— і це був вимір свого дня, коли колір брався лише зі слова крамниці. Відколи
`feed.накласти_збагачення` кладе колір із фото, на тому самому каталозі великих
речей із ТОЧКОЮ більшість (вимір цього прогону друкується нижче). Твердження
переписане на те, що правда тепер: кожна велика річ має НАЗВАНЕ джерело кольору,
і зонна межа стосується рівно зонної частки. Числа тут не зашиті навмисно:
розмір пулу залежить від бюджету символів і від того, що завіз магазин, — проба
друкує те, що виміряла ЦЬОГО прогону, і перевіряє твердження, а не сталу."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, colorspace as cs

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
ГУБИ = "#ceb599"          # колір, що справді лежить у палітрі цієї людини
ВЕЛИКІ = ("верх", "низ", "сукня", "комплект", "верхній_шар")
for мк in (None, {"губи": ГУБИ}):
    сц = dict(вх["сценарій"], **({"макіяж": мк} if мк else {}))
    json.loads(B.виклик("запити", json.dumps(dict(вх, сценарій=сц), ensure_ascii=False)))
    пак = [p for p in B._КЕШ_ПАКЕТА.values() if p.get("кандидати")][-1]
    кат = {c["id"]: c for c in пак["_каталог"]}
    великі = [кат[x["id"]] for сл in ВЕЛИКІ
              for x in (пак["кандидати"].get(сл) or []) if x["id"] in кат]
    зап = пак.get("_запити_у_фід") or []
    з_кулею = sum(1 for q in зап if q.get("не_ближче_за"))
    зонних = sum(1 for c in великі if c.get("джерело_кольору") == "назва_вікно")
    точкою = sum(1 for c in великі if c.get("джерело_кольору") == "фото")
    print("макіяж %-12s → запитів у фід %d, із кулею K-MUA-01 %d · великих у пулі %d "
          "(колір точкою з фото: %d, зоною зі слова: %d)"
          % ("не названо" if not мк else ГУБИ, len(зап), з_кулею, len(великі), точкою, зонних))
    if not мк:
        assert з_кулею == 0, "без названого макіяжу кулі бути не може"
        без_макіяжу = len(великі)
    else:
        assert з_кулею > 0, "названий колір макіяжу мусить ставити кулю на рядки великих слотів"
        print("   пул великих площ: %d → %d" % (без_макіяжу, len(великі)))
        print("   межа: куля ріже точку точно (%d речей), а зону — в центрі (%d речей): "
              "річ, чия зона лише перетинає кулю, лишається законно" % (точкою, зонних))
        assert точкою + зонних == len(великі), ("джерело кольору мусить бути назване в "
                                                "кожної великої речі — мовчазного немає")
