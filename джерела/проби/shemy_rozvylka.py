# -*- coding: utf-8 -*-
"""Рядок 50 БЕКЛОГ: смуги схем розвилки (`bridge.палітри`) на трьох профілях —
чи відповідають вони означенню схеми в корпусі (K-COL-03: «тональна» — один тон,
різна світлота; «аналогова» — сусідні дуги; «нейтралі+акцент» — нейтралі плюс
ОДИН кольоровий; «приглушена комплементарна» — протилежні дуги, приглушена
хрома)? Запуск із теки `джерела`: `python3 проби/shemy_rozvylka.py`."""
import sys, pathlib, json
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import bridge as B, colorspace as cs

БАЗА = json.load(open("стенд_вх.json", encoding="utf-8"))
ПРОФІЛІ = {
    "світлий теплий": dict(шкіра="#deb295", волосся=["#f1dbaa"], очі="#759087"),
    "темний холодний": dict(шкіра="#5a4232", волосся=["#1c1a1a"], очі="#3d4a52"),
    "середній нейтральний": dict(шкіра="#c9a882", волосся=["#6b5842"], очі="#5b5248"),
}

for назва, риси in ПРОФІЛІ.items():
    d = dict(БАЗА, **риси)
    в = json.loads(B.палітри(json.dumps(d, ensure_ascii=False)))
    print("\n=== %s ===" % назва)
    for г in в["гілки"]:
        if not г["реалізована"]:
            continue
        сл, за_роллю = [], {}
        for r in г["ролі"]:
            L, C, h = cs.lch(cs.hx(r["зразок"]))
            сл.append("%s:%s(L%.0f C*%.1f h%.0f роль=%s)" % (r["слот"], r["зразок"], L, C, h, r["роль"]))
            за_роллю.setdefault(r["роль"], (L, C, h))
        print("  %-20s %s" % (г["схема"], " | ".join(сл)))
        # «нейтральна» РОЛЬ у цій СХЕМІ — та, чия хрома притиснута (C*≈0);
        # решта — кольорові ролі, які й звіряються з означенням K-COL-03.
        кольор = {р: (L, C, h) for р, (L, C, h) in за_роллю.items() if C > 1.0}
        h_ряд = [h for _, _, h in кольор.values()]
        if г["схема"] == "тональна" and h_ряд and max(h_ряд) - min(h_ряд) > 3.0:
            print("    РОЗБІЖНІСТЬ: тональна мусить тримати один тон — кути розійшлись: %s"
                  % {р: round(h) for р, (_, _, h) in кольор.items()})
        if г["схема"] == "приглушена_комплементарна" and "домінанта" in кольор and "акцент" in кольор:
            Δh = abs(за_роллю["домінанта"][2] - за_роллю["акцент"][2]) % 360
            Δh = min(Δh, 360 - Δh)
            if not (150 <= Δh <= 210):
                print("    РОЗБІЖНІСТЬ: комплементарна мусить розводити домінанту й акцент ~180° — Δh=%.0f" % Δh)
