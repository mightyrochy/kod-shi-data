"""М-1, В-5: ЧИ НЕСЕ СТРУКТУРА ВСЕ ЇЇ РЕЧЕННЯ ДО ФУНКЦІОНАЛЬНИХ МОДЕЛЕЙ. На шляху шару сирі
слова в моделі не їдуть (`вимоги` порожні, «моделі — зі структурою»), тож усе, що вона сказала,
мусить доїхати полями. Друкує для двох ходів рядок випадку (`паспорт_рядком` — його бачать усі
чотири руки) і які слова її речення (≥4 літер) у ньому є. Лише `мовний_шар` і `паспорт_нагоди`
— та сама проба на main і на гілці. Запуск із `джерела`: python3 проби/шлях_шар_решта.py"""
import sys, os, re
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import мовний_шар as МШ, паспорт_нагоди as ПН

ХОДИ = [("на концерт у Палаці спорту, там завжди холодно в залі і довго стояти в черзі",
         {"event": {"free_text": "концерт у Палаці спорту", "lang": "uk"}, "place": "theatre", "setting": "indoor",
          "quotes": {"place": "концерт", "setting": "в залі"},
          "rest": {"free_text": "там завжди холодно в залі і довго стояти в черзі", "lang": "uk"}}),
        ("хочу, щоб подруга впізнала мене здалеку, бо ми ще не бачились",
         {"goal": "express", "quotes": {"goal": "щоб подруга впізнала мене здалеку"},
          "rest": {"free_text": "бо ми ще не бачились", "lang": "uk"}})]
слова_ = lambda т: {w for w in re.findall(r"[а-яіїєґʼ']{4,}", т.lower())}
разом, дійшло = 0, 0
for слова, в in ХОДИ:
    п = МШ.паспорт_з_шару(в, {}, None, None, слова_ходу=слова)["паспорт"]
    рядок = ПН.паспорт_рядком(п)
    її, є = слова_(слова), слова_(рядок)
    разом, дійшло = разом + len(її), дійшло + len(її & є)
    print("«%s»\n   моделям: «%s»\n   не дійшло: %s" % (слова, рядок, ", ".join(sorted(її - є)) or "—"))
print("ПІДСУМОК: її слів (≥4 літер) %d, до рядка випадку дійшло %d (%d%%)" % (разом, дійшло, 100 * дійшло // разом))
