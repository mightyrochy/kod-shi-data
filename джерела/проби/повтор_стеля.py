# -*- coding: utf-8 -*-
"""Д-1: скільки речей знімає стеля `K_НА_СЛОТ` — та сама сцена двічі.

`композитор_слоти._кандидати_на_слот` ріже слот на `K_НА_СЛОТ` (500) ПІСЛЯ сорту за
колірною відстанню — знімає хвіст рангу, не випадкові речі. Проба збирає ту саму
сцену двічі: з чинною стелею і без неї (піднята до 10⁶ лише в пам'яті процесу, код
не міняється). Де «без стелі» = «зі стелею», стеля в цьому слоті не робить нічого.
Прогін: python3 проби/повтор_стеля.py       (~60 с: два повні збирання)
"""
import json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed as Ф, bridge as B, composer as КМ, композитор_слоти as КС
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), сід=4242, каталог=Ф.каталог_на_диску("каталог_повний.xml"))
_зібрати = КМ.зібрати


def _лічба(стеля):
    """{слот: кандидатів} з одного повного прогону при заданій стелі слота."""
    КС.K_НА_СЛОТ, З = стеля, {}

    def обгортка(F, каталог, **кв):
        р = _зібрати(F, каталог, **кв)
        З.setdefault("к", {с: len(v) for с, v in (р.get("_кандидати") or {}).items()})
        return р
    КМ.зібрати = обгортка; B._КЕШ_ПАКЕТА.clear()
    json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    КМ.зібрати = _зібрати
    return З["к"]

ЧИННА = КС.K_НА_СЛОТ
зі, без = _лічба(ЧИННА), _лічба(10 ** 6)
print("стеля K_НА_СЛОТ = %d (композитор_реєстр.py:84)" % ЧИННА)
print("%-14s %10s %10s %9s" % ("слот", "зі стелею", "без стелі", "знято"))
for с in sorted(без, key=lambda к: -(без[к] - зі.get(к, 0))):
    знято = без[с] - зі.get(с, 0)
    print("%-14s %10d %10d %9s" % (с, зі.get(с, 0), без[с], знято or "—"))
print("РАЗОМ %d проти %d: стеля знімає %d речей = %.0f %% того, що пройшло вікна"
      % (sum(зі.values()), sum(без.values()), sum(без.values()) - sum(зі.values()),
         100.0 * (sum(без.values()) - sum(зі.values())) / sum(без.values())))
