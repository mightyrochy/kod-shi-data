"""K-COL-07 (поділ площ 60-30-10) — від сліду в гейті до рядка у вердикті.

Корпус (тема-4:308): «FORCE: hint · [folkloric constant] — першоджерела не
знайдено, правило позичене з дизайну інтерʼєрів, це пропорція за замовчуванням,
НІКОЛИ не поріг». Виконуваний бік правила живе в `language_gate`: список
ФОЛЬКЛОРНІ_ЧИСЛА ловить «60-30-10» у тексті моделі відколи його дописали 08.09.
Але спрацювання лягало в `мова["фольклорні_числа"]`, а звідти його не читає
ніхто: `_мова_вердикту` і `_мова_порушення` беруть лише `порушення`. Код рахував
і мовчав.
ПІСЛЯ: константа несе ІД КОРПУСУ третім полем, і `перевірити_від_моделі` робить
з неї знахідку. Вето це не тягне — корпус забороняє число ЯК ПОРІГ, не в тексті.
Запуск із теки `джерела`: `python3 проби/col_K-COL-07.py`."""
import json, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import language_gate as LG

ФРАЗА = "Правило 60-30-10 дасть вам збалансований образ."
вх, r, кат, спец = ПВ.стенд(гілка=0)
ід = [x["id"] for с in ("верх", "низ", "взуття", "сумка")
      for x in (r["кандидати"].get(с) or [])[:1]]
з_ід = {п for _, _, п in LG.ФОЛЬКЛОРНІ_ЧИСЛА if п}
print("фольклорних констант у гейті: %d, з них з ід корпусу: %d (%s)"
      % (len(LG.ФОЛЬКЛОРНІ_ЧИСЛА), len(з_ід), ", ".join(sorted(з_ід))))
текст = json.dumps({"версія": "1", "образи": [{"ід": "о1", "речі": ід, "чому": ФРАЗА}]},
                   ensure_ascii=False)
вм = json.loads(ПВ.B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=текст),
                                                     ensure_ascii=False)))
зн = вм["вердикт"]["образи"][0]["знахідки"]
print("ФАКТ · K-COL-07: %s" % ПВ.рядок(зн, "K-COL-07"))
z = next((x for x in зн if x.get("правило") == "K-COL-07"), None)
assert z, "«60-30-10» у тексті моделі не дало знахідки у вердикті"
assert z["сила"] == "hint" and z["сила_нп"] == 0.2, z            # корпусна сила
assert z["регістр"] == "репліка", z                   # фольклорне число не вето
assert (вм.get("мова") or {}).get("можна_видавати") is True, "гейт не має блокувати текст"
print("       ремонт: %s" % z["ремонт"])
print("       видача не заблокована — корпус забороняє число ЯК ПОРІГ, не в тексті")
