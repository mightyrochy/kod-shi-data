# -*- coding: utf-8 -*-
"""каталог_сусіди_лічба.py — СКІЛЬКИ РОЗБОРУ ЗАОЩАДЖУЮТЬ СУСІДИ (наряд 5.4-С, мірило п.1 — без моделі).

Рахує на каталозі на диску (`ФК.каталог_на_диску`), групою прогону `решта`-незалежно (ключ — крамниця + усе, що
бачить модель, крім полів кольору й розміру, `каталог_розбір_сусіди.розбити`):
  · речей, представників (повних розборів), груп сусідів; те саме для наявних (`available`);
  · які поля кольору й розміру є в кожній крамниці (ключі картки, чия назва — з `ПОЛЯ_КОЛЬОРУ`/`ПОЛЯ_РОЗМІРУ`);
  · кольорових викликів: «значення» — унікальних значень кольорових полів, «річ» — по одному на сусіда, чий
    колір не рівний кольору представника; і години за темпу `--повна` (типово 32 с на повну річ) та `--коротка`
    (типово 4 с; виміряна з `секунд` прогін.json частини 1 — підставити).
Групи прогону (`ГРУПИ`) ключа не змінюють: сусіди — в межах групи, а група речі ціла (слот, тип) і залежить від
назви, тож сусіди однієї назви лежать в одній групі.
"""
import argparse
import collections
import os
import sys
import warnings

warnings.filterwarnings("ignore")
ТУТ = os.path.dirname(os.path.abspath(__file__))
ДЖЕРЕЛА = os.path.dirname(ТУТ)
if ДЖЕРЕЛА not in sys.path:
    sys.path.insert(0, ДЖЕРЕЛА)

import фід_каталог as ФК                      # noqa: E402
import фід_розбір as ФР                       # noqa: E402
import каталог_розбір as КР                   # noqa: E402
import каталог_розбір_сусіди as С             # noqa: E402


def лічба(офери, повна, коротка):
    """{ім'я: значення} для списку `офери`."""
    групи = collections.defaultdict(list)
    for o in офери:
        групи[(o.get("магазин"), С.розбити(o)[0])].append(o)
    представників = len(групи)
    сусідів = [o for г in групи.values() for o in г[1:] if С.розбити(o)[1]]
    # Річ без полів кольору колірного виклику не має: повним розбором, як представник.
    повних = len(офери) - len(сусідів)
    різний = [o for г in групи.values() for o in г[1:]
              if С.розбити(o)[1] and С.розбити(o)[1] != С.розбити(г[0])[1]]
    значень = len({С.колір_ключ(o, "значення") for o in різний})
    річ_викликів = len(різний)
    год = lambda п, к: round((п * повна + к * коротка) / 3600, 2)         # noqa: E731
    return dict(речей=len(офери), груп_сусідів_понад_1=sum(1 for г in групи.values() if len(г) > 1),
                представників=представників, сусідів_з_кольором=len(сусідів), повних_розборів=повних,
                сусідів_колір_рівний_представнику=len(сусідів) - len(різний),
                колірних_викликів_значення=значень, колірних_викликів_річ=річ_викликів,
                годин_без_сусідів=год(len(офери), 0), годин_значення=год(повних, значень),
                годин_річ=год(повних, річ_викликів))


if __name__ == "__main__":
    р = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    р.add_argument("--повна", type=float, default=32.0, help="секунд на повну річ")
    р.add_argument("--коротка", type=float, default=4.0, help="секунд на короткий кольоровий виклик")
    а = р.parse_args()
    офери, _ = ФР.читати_yml(ФК.каталог_на_диску(), показ=False)
    for назва, список in (("усі", офери), ("наявні", [o for o in офери if o.get("available")])):
        print(назва, лічба(список, а.повна, а.коротка))
    ключі = collections.defaultdict(collections.Counter)
    for o in офери:
        for к in КР.вхід(o).get("params", {}):
            if к in С.ПОЛЯ_КОЛЬОРУ or к in С.ПОЛЯ_РОЗМІРУ:
                ключі[o.get("магазин")][к] += 1
    print("поля кольору й розміру за крамницями (ключ: речей):")
    for м in sorted(ключі):
        print("  %-28s %s" % (м, ", ".join("%s %d" % (к, n) for к, n in sorted(ключі[м].items()))))
