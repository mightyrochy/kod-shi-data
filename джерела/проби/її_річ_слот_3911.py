"""ЇЇ-РІЧ-СЛОТ (рядки 3911, 4050, 4612): слоти її речі — таблиця слотів внутрішньої мови, а не ваги близькості.
Друкує: скільки слотів має її річ і чи є серед них рукавички; що стає в паспорт з «мої шкіряні рукавички»
(`own_items` зі `slot: gloves`); і «mine» шару фото на кадрі з трьома речами, коли її річ словами — без слота
(рішення #676: «невідомо») і з кодом слота, який схема тепер вимагає (`slot: shoes`, тип і тканина — unknown).
Кращим: 25 слотів, рукавички в паспорті, «mine» закріплює лише взуття. Запуск: cd джерела && python3 проби/її_річ_слот_3911.py"""
import json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import мовний_шар as М, річ_з_фото as Р, внутрішня_мова as ВМ
print("слотів її речі: %d (таблиця внутрішньої мови: %d) · рукавички: %s" % (
    len(Р.СЛОТИ_РЕЧІ), len(ВМ.ТАБЛИЦЯ["slot"]), "рукавички" in Р.СЛОТИ_РЕЧІ))
def річ(цитата, **к):
    return dict({"quote": цитата, "name": {"free_text": цитата, "lang": "uk"}, "status": "has"}, **к)
рук = [річ("мої шкіряні рукавички", slot="gloves", item_type="unknown", fabric="leather")]
пасп = Р.речі_з_json([], [], [], словами=М._її_речі(рук))
print("«мої шкіряні рукавички» → у паспорті:", [(р["слот"], р["матеріал"], р["закріплена"]) for р in пасп] or "—")
КАДР = json.dumps({"items": [
    {"photo": "ф1", "name": "yellow shirt", "slot": "top", "color": "yellow", "formality": 5, "owner": "mine"},
    {"photo": "ф1", "name": "yellow pants", "slot": "bottom", "color": "yellow", "formality": 5, "owner": "mine"},
    {"photo": "ф1", "name": "white sandals", "slot": "shoes", "kind": "sandals", "color": "white", "owner": "mine"}]})
вада = len(пасп) != 1 or пасп[0]["слот"] != "рукавички"
for підпис, власні, треба in (
        ("її річ без слота (#676)", [річ("своє взуття з фото")], []),
        ("її річ зі слотом shoes", [річ("своє взуття з фото", slot="shoes", item_type="unknown", fabric="unknown")],
         ["взуття"])):
    р = Р.речі_з_відповіді_фото(КАДР, [{"ід": "ф1", "ширина": 600, "висота": 900}], власні=власні)["речі_з_фото"]
    моя = [x["слот"] for x in р if x["закріплена"] and x["чия"] == "моя"]
    вада += моя != треба
    print("%-26s → закріплено «твоєю річчю»: %s (треба %s)" % (підпис, моя or "—", треба or "—"))
print("ВАДА" if вада else "OK: її річ має слот із повної таблиці, «mine» — зі слота її речі")
sys.exit(1 if вада else 0)
