# -*- coding: utf-8 -*-
"""Рядок 123: `колір_нейтралі.білі` читає `драп` і не питає про те, на що вже відповіли. ДО: параметра `драп`
у сигнатурі не було ВЗАГАЛІ, K-PC-05 виходило суто за надійністю підтону з фото, і жінка, яка обрала в профілі
плитку «Молочний» (ключ `вершковий`), читала на картці «який білий личить — не визначається з цього фото».
ПІСЛЯ — три стани: знак є (питання нема), «не бачу різниці» (не повторюється, виходить окремий рядок про
неназваний бік), відповіді нема (як доти). І відповідь не глушить питання, а входить у рішення НАЯВНИМ шляхом:
`palette.нейтраль_якір(драп=…)` → K-COL-06-T. Запуск із теки `джерела`: `python3 проби/bilyi_drap_123.py`."""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import colorspace as cs, fit as ПС, pipeline as PL
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
T = ПС.тіло(float(вх["зріст"]), {k: float(v) for k, v in вх["обхвати"].items()})
F = cs.features(cs.hx(вх["шкіра"]), cs.hx(вх["волосся"][0]), cs.hx(вх["очі"]))
ПОВНИЙ = dict(білий="оптичний", метал="срібло", нейтралі="холодні")   # усі три плитки драпіровки
ОБРАЗ = [dict(id="шарф", слот="шарф", hex="#f1dba8", назва="Шарф", тип="шарф", верх_см=140, низ_см=120),
         dict(id="верх", слот="верх", hex="#8a7f74", назва="Светр", тип="светр", верх_см=140, низ_см=95),
         dict(id="низ", слот="низ", hex="#5b4e4d", назва="Штани", тип="штани", верх_см=100, низ_см=5),
         dict(id="взуття", слот="взуття", hex="#22201e", назва="Черевики", тип="черевики", верх_см=10, низ_см=0)]
def знахідки(o, out):                     # те саме дерево, що обходить `стенд_знімок`
    if isinstance(o, dict) and o.get("правило") and ("сила" in o or "суть" in o): out.append(o)
    for v in (o.values() if isinstance(o, dict) else o if isinstance(o, list) else ()): знахідки(v, out)
    return out
def прогін(драп):                         # сценарій стенда «офіс·18°C» зі `стенд_вх.json`
    з = знахідки(PL.перевірити_образ(F, [dict(р) for р in ОБРАЗ], тіло=T, драп=драп,
                 **{k: v for k, v in вх["сценарій"].items() if k != "місце"}), [])
    # дедуплікація (правило, суть) — рівно та, якою `міст_відповіді` будує `в.питання`
    return (sorted({(z["правило"], str(z.get("суть"))[:120]) for z in з if z.get("сила") == "питання"}),
            [z for z in з if z["правило"] in ("K-PC-05", "K-COL-06-T")])
print("Шарф #f1dba8 біля обличчя: L*88.1 C*27.9 b*+27.9 — ТЕПЛИЙ (вершковий) білий у `біле_вікно`.")
for мітка, драп in (("(а) драп=None — відповіді нема", None), ("(б) білий='вершковий' — той самий білий", dict(білий="вершковий")),
                    ("(в) білий='оптичний' — ПРОТИЛЕЖНИЙ білий", dict(білий="оптичний")), ("(в+) усі три плитки, всі холодні", ПОВНИЙ),
                    ("(г) білий='не бачу різниці'", dict(білий="не бачу різниці"))):
    пит, цв = прогін(драп)
    print("\n%s\n   рядків «код не знає»: %d%s" % (мітка, len(пит), "" if цв else "\n   · про білий не сказано нічого"))
    for z in цв: print("   · %-11s сила=%-8s сила_нп=%-5s %s" % (z["правило"], z["сила"], z.get("сила_нп"), z["суть"]))
    assert any(z["правило"] == "K-PC-05" for z in цв) == (not (драп or {}).get("білий") or драп["білий"] == "не бачу різниці")
пит0, пит1 = прогін(None)[0], прогін(ПОВНИЙ)[0]
print("\nСценарій стенда, профіль відповів на всі три плитки драпіровки: рядків «код не знає» %d → %d (пішло: %s)"
      % (len(пит0), len(пит1), " | ".join(с for _, с in sorted(set(пит0) - set(пит1))) or "—"))
assert [p for p, _ in set(пит0) - set(пит1)] == ["K-PC-05"] and not set(пит1) - set(пит0)
print("bilyi_drap_123: зелено")
