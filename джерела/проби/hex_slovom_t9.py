# -*- coding: utf-8 -*-
"""Т-9: hex, що стоїть на місці кольору, стає українським словом; зі словом — ні.

Дві фрази зі звіту 25.09 (`аудит/тести/2026-09-25_прохід_2.md`, Т-9) і дві, які вже
працювали, плюс лічба по всіх прозах рук 3–4, що є в репозиторії (заглушки стенда
рв6 й наскрізного тесту та проза зі звіту). ДО: показ знімав hex як машинний слід,
і «колір #f5f5dc, денім» читалось на картці «колір, денім» — слово без кольору.
ПІСЛЯ: число перекладає код (`розбір_відповідей.hex_словами` → `verify.слово_з_lab` над
вікнами ЛЕКСИКОНУ — те саме, що кличе жниварка), і лише там, де в сегменті біля числа
нема жодного слова, крім його ярлика («колір», «hex»)."""
import sys, os, re
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import розбір_відповідей as Р

ЗНЯТИ = lambda s: re.sub(r"\s+([,.;:])", r"\1", re.sub(r"#[0-9a-fA-F]{6}\b", "", s)).strip()
ФРАЗИ = ["довжина до щиколотки, колір #f5f5dc, денім", "довжина до талії, колір #fffaf0, легкий батист",
         "колір ніжно-блакитний (#E0F7FA)", "колір графіт (hex #2C2F33)"]
ПРОЗИ = {
    "звіт 25.09 · рука 3": "\n".join(ФРАЗИ),
    "заглушка рв6_стенд": "1. Речі:\n- блуза, прямий крій, до стегна, молочна #efe6d8, віскоза\n"
        "- штани, звужені, повна довжина, темно-сині #1f2a44, вовна\n"
        "2. Взуття й аксесуари: лофери, чорні #111111, шкіра; сумка через плече, коньячна #8b5a2b, шкіра.",
    "заглушка наскрізь.js": "**1. Речі**\n* Базовий топ: сорочка лляна пісочна, вільна (#D8C3A5)\n* Штани: "
        "широкі штани бежеві (#C9B79C)\n* Взуття: сандалі шкіряні (#8B6F47)\n* Сумка: сумка плетена (#A67B5B)",
    "рука 3 без слова кольору": "- кардиган оверсайз, до стегна, #c9b79c, вовна",
    "слово моделі поза лексиконом": "сумка через плече, коньячна #8b5a2b, шкіра",
}
for ф in ФРАЗИ:
    print("   ДО «%s» · ПІСЛЯ «%s»" % (ЗНЯТИ(ф), ЗНЯТИ(Р.hex_словами(ф))))
усього = перекладено = 0
for ім, т in sorted(ПРОЗИ.items()):
    б, с = len(Р._HEX_РЕГ.findall(т)), len(Р._HEX_РЕГ.findall(Р.hex_словами(т)))
    усього += б; перекладено += б - с
    print("   %-28s hex %d · стало словом %d · зі словом поруч %d" % (ім, б, б - с, с))
print("hex_словами: hex усього %d · стали словом %d · зі словом поруч (лишились) %d"
      % (усього, перекладено, усього - перекладено))
assert Р.hex_словами("колір #f5f5dc, денім") == "колір вершковий, денім"
assert Р.hex_словами("колір ніжно-блакитний (#E0F7FA)") == "колір ніжно-блакитний (#E0F7FA)"
assert Р.hex_словами("коньячна #8b5a2b") == "коньячна #8b5a2b", "слово моделі поза лексиконом — теж слово"
print("hex_slovom_t9: зелено")
