# -*- coding: utf-8 -*-
"""K-OUT-44 (хлорид кальцію проти вовни, шовку й шкіри) — живим шляхом.

ДО ПРАВКИ: `outer.догляд` читала РІВНО `реагенти`; `темп_c` і `опади` стояли в
сигнатурі й не вживались — названий випадок із `аудит/КЛАС_МЕРТВІ_ПАРАМЕТРИ.md`
(«порада про догляд не залежить від дощу»). А `реагенти` — прапорець, якого не
ставить ні стенд, ні тест живого шляху, ні показ. Отже обидва правила сольової
осі не мали ЖОДНОГО живого шляху.
ПІСЛЯ: сльота виводиться з погоди (мокрий сніг при ≤ +4 °C — смуга з реєстру
модуля, T3), і рядок стоїть у `вердикт.образи[0].знахідки`."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, outer as OU

print("вживані параметри `догляд`:", OU.догляд.__code__.co_varnames[:4],
      "· смуга сльоти ≤ %+.0f °C" % OU.C["сльота_темп_c"])
вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
вх["сценарій"].update(темп_c=-2, опади="мокрий_сніг")
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
к = з["кандидати"]
взяти = lambda сл, ум: next((кат[r["id"]] for r in (к.get(сл) or [])
                             if r["id"] in кат and ум(кат[r["id"]])), None)
вовняне = взяти("верхній_шар", lambda c: (c.get("вовна_частка") or 0) >= 0.6
                or "вовн" in str(c.get("матеріал") or ""))
ід = [r["id"] for r in (вовняне, взяти("сукня", lambda c: True),
                        взяти("взуття", lambda c: True)) if r]
print("верхній шар:", вовняне["назва"][:50], "· склад:", str(вовняне.get("матеріал"))[:34])
for сц in (dict(темп_c=-2, опади="мокрий_сніг"), dict(темп_c=12, опади="дощ")):
    вм = json.loads(B.виклик("від_моделі", json.dumps(
        dict(вх, сценарій=dict(вх["сценарій"], **сц), ід=ід), ensure_ascii=False)))
    зн = ((вм.get("вердикт") or {}).get("образи") or [{}])[0].get("знахідки") or []
    р = next((z for z in зн if z.get("правило") == "K-OUT-44"), None)
    print("%+3.0f°C %-12s → K-OUT-44: %s" % (сц["темп_c"], сц["опади"],
          "нема (не сльота)" if not р else "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:48])))
