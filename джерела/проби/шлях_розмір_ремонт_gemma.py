# -*- coding: utf-8 -*-
"""Ремонт (ітерація 2) не наближається до стелі мосту (400000 симв, запас ~75%),
але впритул підходить до КОНТЕКСТУ ноутбукової gemma-4-12b (61440 токенів,
джерело — аудит/ПЕРЕДАЧА.md §0: «промпт ремонту ~50 тис. токенів … запас 5.8 тис.;
саме він ламає JSON»). Проба будує СПРАВЖНІЙ промпт_ремонту РЕАЛЬНИМ пайплайном
(bridge, каталог_повний) і зіставляє з виміром сирих прогонів ноутбука 25.09
(аудит/тести/сирі_2026-09-25/: 84798-123686 симв на цьому самому кроці,
~2.26 симв/токен — аудит/тести/2026-09-25_прохід_2.md:213-215). Друкує факт.
Запуск: cd джерела && python3 проби/шлях_розмір_ремонт_gemma.py"""
import json, os, sys
_КОРІНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _КОРІНЬ)
import bridge as B, feed as Ф

вх = json.load(open(os.path.join(_КОРІНЬ, "стенд_вх.json"), encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
пул = json.loads(r["руки"]["1"])["пул"]
н = lambda с, k: пул[с][k % len(пул[с])]["н"]
образи = [dict(ід="о%d" % (і + 1), підпис="тихий беж", полюс="баланс", день="День у місті.",
               речі=[н("верх", і), н("низ", і), н("взуття", і), н("сумка", і)]) for і in range(10)]
т = json.dumps(dict(версія="1", образи=образи), ensure_ascii=False)
в = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=т), ensure_ascii=False)))
симв = len(в["промпт_ремонту"])

СИМВ_НА_ТОКЕН_GEMMA, КОНТЕКСТ_GEMMA, СТЕЛЯ_МОСТУ = 2.26, 61_440, 400_000
токенів = round(симв / СИМВ_НА_ТОКЕН_GEMMA)
запас_gemma = КОНТЕКСТ_GEMMA - токенів - 4000   # 4000 = стеля виводу (СТЕЛЯ_ВИХОДУ, worker.js)
print("промпт_ремонту (bridge, каталог_повний):", симв, "симв ≈", токенів, "токенів на gemma")
print("контекст gemma:", КОНТЕКСТ_GEMMA, "токенів − стеля виводу 4000 − цей промпт → запас:", запас_gemma, "токенів")
print("стеля мосту 400000 симв: запас %.0f%% (порівняно з ~%.0f%% на контексті gemma)"
      % (100 * (СТЕЛЯ_МОСТУ - симв) / СТЕЛЯ_МОСТУ, 100 * запас_gemma / КОНТЕКСТ_GEMMA))
assert симв < 0.5 * СТЕЛЯ_МОСТУ, "ремонт раптом наблизився до стелі мосту"
assert 84_000 <= симв <= 130_000, "розмір промпту ремонту вийшов за вимірений на сирих прогонах діапазон"
assert запас_gemma < 0.25 * КОНТЕКСТ_GEMMA, "запас gemma тепер комфортний — перевір, чи це досі та сама вада"
