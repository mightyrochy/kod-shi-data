"""Звірка двох знімків `е3_pal16_знімок.py`; аргументи: ДО.json.gz ПІСЛЯ.json.gz. Друкує зміни полів і ваги."""
import collections, gzip, json, sys

ПОЛЯ = ['вхід', 'суть', 'речі', 'сила', 'блокує', 'сила_нп', 'під_підлогою', 'опора', 'учасники', 'заяви',
        'де_ламається', 'сума']


def main():
    """Ті самі входи в тому самому порядку; зміни — за полем і за парою ваг (ДО → ПІСЛЯ)."""
    до, після = (json.load(gzip.open(ш, 'rt', encoding='utf-8')) for ш in sys.argv[1:3])
    assert [x[0] for x in до] == [x[0] for x in після], 'різні входи'
    поля, ваги = collections.Counter(), collections.Counter()
    for а, б in zip(до, після):
        поля.update(п for і, п in enumerate(ПОЛЯ) if а[і] != б[і])
        ваги[('опора' if а[7] else 'зауваження', а[0].split('|')[1], а[5], б[5], а[6], б[6])] += 1
    print('знахідок K-PAL-16: ДО %d, ПІСЛЯ %d' % (len(до), len(після)))
    print('змінені поля:', dict(поля))
    print('| вид | частка вікна | вага ДО | вага ПІСЛЯ | під підлогою ДО → ПІСЛЯ | знахідок |')
    print('|---|---|---|---|---|---|')
    for (в, ч, а, б, па, пб), н in sorted(ваги.items()):
        print('| %s | %s | %s | %s | %s → %s | %d |' % (в, ч, а, б, па, пб, н))


if __name__ == '__main__':
    main()
