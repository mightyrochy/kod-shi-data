"""Інтервал золота лишається в доборі поруч із виміряним кандидатом."""
import sys
sys.path.insert(0, ".")
import композитор_слоти as С, verify as В, фід_збагачення as З, feed as Ф


def головна():
    """Порівняти штатний добір одного намиста й змішаного пулу без фолбека."""
    р = dict(id="слово-золото", слот="намисто", тип="намисто", метал="золото",
             lab=None, колір_тип="інтервал", впевненість=1,
             колір_не_вимір=З.не_вимір_кольору(В.ЛЕКСИКОН["золотий"], "золотий", "shop_word"))
    вимір = dict(id="фото-золото", слот="намисто", тип="намисто", метал="золото",
                 lab=(70, 15, 40), колір_тип="вимір", впевненість=1)
    q = dict(слот="намисто", метал="золото", L_min=0, L_max=100, C_min=0, C_max=100,
             h_from=40, h_to=110)
    результати = []
    for речі in ([р], [р, вимір]):
        пул = С.кандидати_на_слот(речі, [q], "намисто")[0]
        рядки = {x["id"]: x.get("_вікно") is not None for x in пул}
        результати.append(рядки)
    print("Соло й поруч із виміром:", результати)
    assert all(x.get(р["id"]) for x in результати)
    assert Ф.описує_річ(р, q) and not Ф.описує_річ(р, dict(q, метал="срібло"))
    assert not Ф.описує_річ(dict(р, колір_тип="невідомо"), q)
    assert not Ф.описує_річ(dict(lab=(70, 20, 62)), q)


if __name__ == "__main__":
    головна()
