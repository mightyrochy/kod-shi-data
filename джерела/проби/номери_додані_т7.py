# -*- coding: utf-8 -*-
"""Т-7 · номер речі «#N·MM» — номер і код магазину, і модель називає річ обома. Річ, додана в пул посеред петлі
(«потрібно» моделі → `за_запитом`), буває з крамниці, якої в пулі нема. Чи міняються від неї номери речей пулу, які
модель уже бачила й назвала в попередній відповіді? Пул — пакет `стенд_вх.json`; для кожної крамниці каталогу поза
пулом (з річчю в слоті пулу) додається одна її річ. Друкує факт: скільки старих пар «номер·код» після цього вже
не резолвиться в ту саму річ (такі речі розбір кладе в `невірні_пари` — зі складу образу вони випадають).
Запуск: cd джерела && python3 проби/номери_додані_т7.py"""
import copy, json, os, sys
Д = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, Д); os.chdir(Д)
import bridge as B, feed, міст_пакет as МП, пакет_моделі as PL, розбір_відповідей as РВ; feed.каталог_на_диску()
json.loads(B.виклик("запити", json.dumps(json.load(open("стенд_вх.json")), ensure_ascii=False)))
канд = МП._КЕШ_ПАКЕТА[МП._ОСТАННІЙ_ПАКЕТ[-1]]["кандидати"]
маг = lambda r: (r.get("id") or "").split("@")[-1]
в_пулі = {маг(r) for рч in канд.values() for r in рч}
ном0 = PL.номери_речей(канд)[0]
поза = {}
for r in B.каталог_останнього_пакета():
    if маг(r) not in в_пулі and r.get("слот") in канд:
        поза.setdefault(маг(r), r)
втрачено = {}
for м, r in sorted(поза.items()):
    к = copy.copy(канд); к[r["слот"]] = list(к[r["слот"]]) + [dict(r, за_запитом="проба")]
    за_ном = РВ._за_номером(к)
    втрачено[м] = sum(1 for і, (n, код) in ном0.items() if за_ном.get(n) != (і, код))
гірше = max(втрачено.items(), key=lambda кв: кв[1]) if втрачено else ("—", 0)
print("ФАКТ · пул %d речей із %d крамниць · крамниць поза пулом із річчю в слоті пулу: %d" % (len(ном0), len(в_пулі), len(поза)))
print("ФАКТ · додана річ із такої крамниці ламає пари «номер·код» пулу: у %d крамницях із %d; найгірше — %s: %d з %d номерів"
      % (sum(1 for в in втрачено.values() if в), len(втрачено), гірше[0], гірше[1], len(ном0)))
print("ФАКТ · номери самої доданої речі — після пулу: %s" % all(
    РВ._за_номером(dict(канд, **{r["слот"]: list(канд[r["слот"]]) + [dict(r, за_запитом="проба")]}))
    .get(len(ном0) + 1, (None,))[0] == r["id"] for r in поза.values()))
