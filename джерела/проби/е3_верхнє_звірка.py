"""Звірити два знімки ваг `верхнє_суд` / `верхнє_догляд` (`е3_верхнє_знімок.py` чи
`е3_верхнє_гейти.py`): склад, сила й `блокує` тотожні; таблиця змін сирої й ефективної ваги."""
import collections, gzip, json, sys


def main():
    """Друк таблиць «правило · ДО · ПІСЛЯ · кількість» для сирої й ефективної ваги."""
    def читати(шлях):
        with gzip.open(шлях, 'rt', encoding='utf-8') as ф:
            д = json.load(ф)
        return д['записи'] if isinstance(д, dict) else д
    до, після = map(читати, sys.argv[1:3])
    assert len(до) == len(після), (len(до), len(після))
    сирі, ефективні, правила = collections.Counter(), collections.Counter(), collections.Counter()
    for д, п in zip(до, після):
        assert д[:7] == п[:7], (д, п)
        правила[д[2]] += 1
        if д[7] != п[7]:
            сирі[д[2], д[5], д[7], п[7]] += 1
        if д[8] != п[8]:
            ефективні[д[2], д[5], д[8], п[8]] += 1
    print('знахідок', len(до), '— склад, сила й блокує тотожні; правил', dict(правила))
    for назва, т in (('сирі', сирі), ('ефективні', ефективні)):
        print('\n%s зміни: %d' % (назва, sum(т.values())))
        if т:
            print('| правило | сила | ДО | ПІСЛЯ | кількість |\n|---|---|---|---|---|')
            for (пр, с, б, ст), к in sorted(т.items(), key=str):
                print('| %s | %s | %s | %s | %d |' % (пр, с, б, ст, к))


if __name__ == '__main__':
    main()
