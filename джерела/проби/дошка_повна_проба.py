# -*- coding: utf-8 -*-
"""Вимірює всю дошку ДО → ПІСЛЯ згортання фрагментів на тимчасовій копії."""
import shutil, sys, tempfile
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'прилади'))
import згорнути_дошку as згортання
from дошка_поля import метадані, перевірити_поля
from дошка_зріз import читати_дошку


def помилки_джерела(шлях):
    """Лічить помилки джерела на всіх датованих рядках, незалежно від номера."""
    вади = []
    for рядок in шлях.read_text(encoding='utf-8').splitlines():
        if not згортання.РЯДОК.match(рядок):
            continue
        від, до = згортання.межі_стану(рядок)
        решта = рядок[:від] + рядок[до:]
        if 'дата' in метадані(решта):
            вади += [п for п in перевірити_поля(решта, новий=True, рядок=рядок) if 'поле виявлено:' in п]
    return len(вади)


if __name__ == '__main__':
    з = Path(згортання.КОРІНЬ)
    print('ДО: помилок джерела', помилки_джерела(з / 'аудит/БЕКЛОГ.md'))
    with tempfile.TemporaryDirectory() as тека:
        т = Path(тека); дошка = т / 'дошка.md'; shutil.copyfile(з / 'аудит/БЕКЛОГ.md', дошка)
        (т / 'фрагменти').mkdir()
        if (з / 'аудит/дошка').is_dir():
            shutil.copytree(з / 'аудит/дошка', т / 'фрагменти', dirs_exist_ok=True)
        згортання.КОРІНЬ, згортання.ДОШКА, згортання.ТЕКА = тека, str(дошка), str(т / 'фрагменти')
        звіт, вади = згортання.згорнути(True); print('Перевірка:', звіт); assert not вади, вади
        звіт, вади = згортання.згорнути(); print('Згортання:', звіт); assert not вади, вади
        після = помилки_джерела(дошка); print('ПІСЛЯ: помилок джерела', після); assert після == 0
        записи, давні, вади_зрізу = читати_дошку(дошка); assert not вади_зрізу, вади_зрізу
        print(f'читати_дошку: без винятку; з полями {len(записи)}, давніх без полів {давні}')
        assert not перевірити_поля('<!-- дошка: дата=2026-10-17 -->', рядок='; виявлено: диспетчер;')
        assert перевірити_поля('<!-- дошка: дата=2026-10-17 -->', рядок='; виявлено: вигадане;')
        print('Джерело «диспетчер» прийнято; вигадане відхилено')
