# -*- coding: utf-8 -*-
"""Рядок 133: тріада й приглушена комплементарна — кольори на ВЕЛИКИХ речах, площі рахує код.
Профіль стенда + основа «олива» (як у власниці 22.09), офіс 18 °C, каталог_повний. ДО — старі
записи `СХЕМИ` (ролі `ДЕФОЛТ_РОЛЕЙ`, секундант нейтраль/ТИХО, відлуння на аксесуари), підставлені
в той самий словник; ПІСЛЯ — чинні. Друкує голови пулу (детермінований читач: верх, низ, взуття,
сумка), сім'ї на великих речах із площами і суд K-COL-03 над образом власниці (нейтральні великі
речі + сумка кольору схеми). Запуск із `джерела`: PYTHONPATH=. python3 проби/tryada_ploshchi_133.py"""
import json, sys; sys.path.insert(0, ".")
import bridge as B, palette as P, fit as ПС, міст_пакет as МП, міст_вхід as МВ
ОЛ = dict(база="оливковий·тепла·50·середні", база_hex="#7b7a3b", база_тип="колір", насиченість="середні")
ТИХО, ПР, дуга = P.ТИХО, P.ПРИГЛУШЕНО, P._дуга
ДО = {"тріада": dict(P.СХЕМИ["тріада"], хрома=dict(домінанта=ПР, секундант=ТИХО, акцент=(28.0, 50.0)),
                     відлуння=True, поверхні=None, ролі=None),
      "приглушена_комплементарна": dict(P.СХЕМИ["приглушена_комплементарна"], відлуння=True, поверхні=None,
          ролі=None, хрома=dict(домінанта=ПР, секундант=ТИХО, акцент=(24.0, 45.0)),
          тон=lambda h: dict(домінанта=дуга(h, 18), секундант="нейтраль", акцент=дуга((h+180) % 360, 18)))}
вх0 = json.load(open("стенд_вх.json", encoding="utf-8"))
T = ПС.тіло(float(вх0["зріст"]), {k: float(v) for k, v in вх0["обхвати"].items()})
for схема, старий in ДО.items():
    вх, нова = dict(вх0, вибір_кольору=ОЛ, схема=схема), P.СХЕМИ[схема]
    сім = P.специфікація(МВ._збірка(МВ._нормалізувати_вхід(вх))[0], схема, ["верх"], якір_тон=ОЛ["база_hex"])["сім_ї_схеми"]
    власниці = None
    for мітка, запис in (("ДО", старий), ("ПІСЛЯ", нова)):
        P.СХЕМИ[схема] = запис; МП._КЕШ_ПАКЕТА.clear()
        к = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["кандидати"]
        кат = {c["id"]: c for c in B.каталог_останнього_пакета()}; ф = lambda і: P.сім_я_схеми(кат[і]["lab"], сім)
        голови = [dict(кат[к[с][0]["id"]], слот=с) for с in ("верх", "низ", "взуття", "сумка") if к.get(с)]
        пл = P.площі_схеми(голови, сім, T)
        print("%s · %s · голови: %s\n   великі несуть %d/%d сімей · площі %s · колір лише на аксесуарах: %s" % (
            схема, мітка, " · ".join("%s %s (%s)" % (г["слот"], г["id"], ф(г["id"]) or "нейтраль") for г in голови),
            sum(1 for v in пл["сім_ї"].values() if v["слоти"]), len(сім),
            {р: v["частка"] for р, v in пл["сім_ї"].items() if v["частка"]} or "—",
            sorted({сл for v in пл["аксесуари"].values() for сл, _ in v}) or "—"))
        власниці = власниці or [next(x["id"] for x in к[с] if not ф(x["id"])) for с in ("верх", "низ")] + [
            next(i for i, c in sorted(кат.items()) if c["слот"] == "сумка" and ф(i) == сім[-1]["роль"])]
        зн = [z for z in json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=власниці), ensure_ascii=False)))
              ["вердикт"]["образи"][0]["знахідки"] if z.get("правило") == "K-COL-03"]
        print("   образ власниці %s → K-COL-03: %s" % (власниці, ("%s %.2f %s · %s" % (
            зн[0]["сила"], зн[0]["сила_нп"], зн[0]["регістр"], зн[0]["суть"])) if зн else "НЕМА"))
    P.СХЕМИ[схема] = нова
