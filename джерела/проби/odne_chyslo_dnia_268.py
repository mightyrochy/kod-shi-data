# -*- coding: utf-8 -*-
"""#268 (рядок 210): одне число про той самий день. Тестувальниця на прогоні
`zlyttia_268_moroz` побачила в ОДНОМУ звіті власника два різні числа: у рядку випадку
одне, а в суті K-WEA-05 «(сніг, −2 °C)» — інше. Причина: температуру форматували
НЕЗАЛЕЖНО — рядок випадку `"%g °C"` (`паспорт_нагоди`), суть і «звідки» солі
`"%+.0f °C"`. На цілому числі збігались, на дробовому — ні, а дробову температуру в
паспорт підставляє МОДЕЛЬ (З-5г). ДО — модулі origin/main, ПІСЛЯ — робоче дерево.
Запуск із теки `джерела`: PYTHONPATH=. python3 проби/odne_chyslo_dnia_268.py"""
import subprocess, sys, types; sys.path.insert(0, ".")
import сценарій as СЦ, аксесуари_погода as АП, паспорт_нагоди as ПН
def з_main(ім):
    м = types.ModuleType(ім); м.__dict__["__name__"] = ім
    exec(subprocess.run(["git", "show", "origin/main:джерела/%s.py" % ім],
                        capture_output=True, text=True).stdout, м.__dict__)
    return м
АПд, ПНд = з_main("аксесуари_погода"), з_main("паспорт_нагоди")
РІЧ = dict(id="п-1", слот="взуття", назва="Черевики замшеві графітові", матеріал="натуральна замша")
def суть(М, t):
    зн = [з for з in М.сезон_і_погода([РІЧ], темп_c=t, опади="сніг") if з["правило"] == "K-WEA-05"]
    return зн[0]["суть"] if зн else "нема"
рядок = lambda М, t: "%g °C" % float(t) if М is ПНд else М._СЦ_ТЕМП(t)
ТЕМПИ = (-8.0, -2.0, -2.4, -7.5, -0.4, 2.5, 18.0)
дс = пс = сухо = 0
print("те саме число в рядку випадку і в суті K-WEA-05 (річ: %s)" % РІЧ["назва"])
print("темп_c | ДО: рядок / суть                | ПІСЛЯ: рядок / суть")
for t in ТЕМПИ:
    rд, sд = рядок(ПНд, t), суть(АПд, t)
    rп, sп = рядок(ПН, t), суть(АП, t)
    if sд == sп == "нема": сухо += 1; continue      # вище смуги солі (+2 °C) умови нема
    дс += rд not in sд; пс += rп not in sп
    print("%6g | %-9s %-9s %-7s | %-9s %-9s %s" % (t, rд, sд.split("(сніг, ")[-1].rstrip(")"),
          "РОЗБІГ" if rд not in sд else "збіг", rп, sп.split("(сніг, ")[-1].rstrip(")"),
          "РОЗБІГ" if rп not in sп else "збіг"))
print("розбіжних чисел про той самий день: ДО %d з %d → ПІСЛЯ %d з %d (%d поза смугою солі)"
      % (дс, len(ТЕМПИ) - сухо, пс, len(ТЕМПИ) - сухо, сухо))
print("ДО   при −2.4 °C: суть «%s» · рядок випадку «%s»" % (суть(АПд, -2.4), рядок(ПНд, -2.4)))
print("ПІСЛЯ при −2.4 °C: суть «%s» · рядок випадку «%s»" % (суть(АП, -2.4), рядок(ПН, -2.4)))
print("«звідки» солі тим самим числом: %s" % СЦ.сіль_на_дорозі(None, -2.4, "сніг")[1])
