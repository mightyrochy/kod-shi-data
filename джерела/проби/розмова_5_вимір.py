# -*- coding: utf-8 -*-
"""РОЗМОВА-5 (рядки 1438, 1439, 1441, 314): що мовна модель пише в ході розмови — лічба по записах VIDPOVIDI
живого прогону (`*хід_розмови*.txt`), ДО і ПІСЛЯ на тих самих сценах. Регекси — мірило проби, не код продукту.
Запуск: python3 проби/розмова_5_вимір.py <тека VIDPOVIDI> [<тека> …] (теки обходяться вглиб). «на_ви» — грубо: «ви з ним»
(вона й супутник) теж рахується, тож дивитись очима."""
import glob, json, os, re, sys
ТРЕТЯ = re.compile(r"стиліст|помічниц|застосун|\bкод\b", re.I)
ОБІЦЯНКА = re.compile(r"\b(буде|будуть|не буде|підберу|зберу|складу|врахую|додам|оберу|запропоную)\b", re.I)
ВИ = re.compile(r"\b(ви|вас|вам|ваш\w*|захочете|розкажіть|можете|плануєте|хочете)\b", re.I)
def обʼєкт(т):
    т = re.sub(r"^```(json)?|```$", "", т.strip()).strip()
    try: return json.loads(т[т.find("{"):т.rfind("}") + 1])
    except ValueError: return None
р = dict(ходів=0, need_не_none=0, третя_особа=0, обіцянка_none=0, запрошень=0, сьогодні=0, на_ви=0, без_крапки=0, теми_поза_умовою=0)
for тека in sys.argv[1:]:
    for ф in sorted(glob.glob(os.path.join(тека, "**", "*хід_розмови*.txt"), recursive=True)):
        промпт, _, відп = open(ф, encoding="utf-8").read().partition("── ВІДПОВІДЬ")
        о, п = обʼєкт(відп.split("\n", 1)[-1]), обʼєкт(промпт.split("\n", 1)[-1]) or {}
        if not isinstance(о, dict) or "text" not in о: continue
        т, з = str(о.get("text") or ""), str(о.get("invite") or "")
        р["ходів"] += 1
        if о.get("need") not in (None, "none"):
            р["need_не_none"] += 1; р["третя_особа"] += bool(ТРЕТЯ.search(т))
        else: р["обіцянка_none"] += bool(ОБІЦЯНКА.search(т))
        р["на_ви"] += bool(ВИ.search(т + " " + з))
        if з:
            р["запрошень"] += 1; р["сьогодні"] += "сьогодні" in з.lower()
            р["без_крапки"] += bool(т.strip()) and not re.search(r"[.!?…][»)\"]*$", т.strip())
            if "advice_topics_if" in п:   # ПІСЛЯ: теми з «_if» — лише якщо її слова зробили умову правдивою
                р["теми_поза_умовою"] += bool(set(о.get("invite_topics") or []) - set(п.get("advice_topics") or []))
print(" · ".join("%s %d" % кв for кв in р.items()))
print("третя_особа — із need≠none; обіцянка — із need=none; сьогодні, без_крапки — із запрошень; "
      "теми_поза_умовою — запрошення з темою не з advice_topics (лише промпти ПІСЛЯ), її судить суд частин")
