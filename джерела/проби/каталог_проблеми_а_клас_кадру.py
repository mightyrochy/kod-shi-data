"""Реєстр А (рядок 5630), клас А5: що зображено на кадрі (на моделі, ціла річ, деталь, підошва,
етикетка, інша річ). Клас плитки міряв лише прогін галерей ноутбука (`каталог_кадри.json.gz`,
аркуш qwen3-vl). Друкує розподіл класів кадрів галерей, покриття за слотом речі (скільки речей
кожного слота має виміряну галерею) і скільки записів збагачення несуть клас свого кадру жнив.
Запуск: cd джерела && python3 проби/каталог_проблеми_а_клас_кадру.py"""
import collections, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed as Ф, фід_кадр_колір as ФКК
from жнива_промпти import тип_речі
оф = Ф.читати_yml(Ф.каталог_на_диску("каталог_повний.xml"))[0]
зб, кадри = Ф.читати_збагачення(), ФКК.читати_кадри()
класи = collections.Counter(в.get("клас") or "без класу" for вв in кадри.values() for в in вв)
print("кадрів галерей %d у %d речах · класи:" % (sum(класи.values()), len(кадри)), dict(класи.most_common()))
слоти, виміряні = collections.Counter(), collections.Counter()
for o in оф:
    с = тип_речі(o)[1]
    слоти[с] += 1; виміряні[с] += o["id"] in кадри
print("покриття галерей за слотом (виміряно/речей):", ", ".join("%s %d/%d" % (с, виміряні[с], н) for с, н in слоти.most_common()))
з_класом = sum(1 for з in зб.values() if isinstance(з, dict) and (з.get("клас") or з.get("клас_кадру")))
print("записів збагачення з класом кадру жнив: %d з %d" % (з_класом, len(зб)))
