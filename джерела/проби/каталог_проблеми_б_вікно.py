"""Реєстр проблем каталогу, напрям Б, клас Б4: межі вікон коду кольору вирішують, чий колір лишиться — слова чи фото.
Рядки 59, 211, 266, 1112, 2852, 3991, 4661–4663, 4790/4920. ФАКТ — як код звів слово крамниці з виміром кадру
(поле `колір_назва_за_чим`, лапки знято): збіг слова, та сама сім'я поза вікном слова, інша сім'я у вікні вжитку;
і сім'ї лексикону, у які вписано слова, що їх людина бачить різними (капучино ↔ срібний ↔ сірий).
Запуск: cd джерела && python3 -W ignore проби/каталог_проблеми_б_вікно.py"""
import collections, os, re, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as FK, verify as V
К = FK._прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"]
ф = [r for r in К if r.get("колір_hex_фото")]
рід = collections.Counter((r["колір_назва_джерело"], re.sub(r"«[^»]*»", "«…»", r.get("колір_назва_за_чим") or "")[:80]) for r in ф)
print("ФАКТ · виміряних записів %d; як зведено слово крамниці з виміром:" % len(ф))
for (дж, чому), н in рід.most_common(9):
    print("   %5d  %-9s %s" % (н, дж, чому))
інша = sum(н for (дж, ч), н in рід.items() if "інша сім'я, але вимір лежить у вікні вжитку" in ч)
поза = sum(н for (дж, ч), н in рід.items() if "вікно не всередині" in ч)
print("ФАКТ · слово лишилось, хоч сім'я виміру інша (вирішило вікно вжитку): %d (%.1f %%); та сама сім'я, вимір поза "
      "вікном слова: %d (%.1f %%)" % (інша, 100 * інша / len(ф), поза, 100 * поза / len(ф)))
сім = collections.defaultdict(list)
for сл in V.ЛЕКСИКОН:
    сім[V.сім_я_слова(сл)].append(сл)
print("ФАКТ · сім'ї лексикону: %d слів у %d сім'ях; сіра: %s" % (len(V.ЛЕКСИКОН), len(сім), sorted(сім["сіра"])))
