"""K-REG-05 (конфліктна пара реєстрів) на живому шляху. Запуск із теки
`джерела`: `python3 проби/reg_K-REG-05.py`.

Пара береться з таблиці ЧАСТИНИ III теми-13, а не вигадується: там їх рівно
чотири — класика × gorpcore, преппі × gorpcore, романтичний × воркер,
тиха розкіш × стритвер. «Класика × гранж» серед них НЕМА, тому проба бере ту з
чотирьох, яку живий пул стенда справді дає.

Правило показує обидві половини своєї механіки: конфліктна пара ШТРАФУЄТЬСЯ
(знахідка з вагою у вердикті), когерентна НЕ ПРЕМІЮЄТЬСЯ (жодного рядка)."""
import json, sys, pathlib, itertools
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B, реєстри as РЕ

вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["гілка"] = 0
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
пул = json.loads(r["руки"]["1"])["пул"]
за_реєстром = {}
for с, речі in пул.items():
    for р in речі:
        if р.get("реєстр"):
            за_реєстром.setdefault(РЕ.ключ_реєстру(р["реєстр"]) or р["реєстр"], []).append((с, р["н"]))

пара = next((п for п in РЕ.КОНФЛІКТНІ if all(k in за_реєстром for k in п)), None)
print("конфліктні пари теми-13:", [" × ".join(sorted(п)) for п in РЕ.КОНФЛІКТНІ])
print("пара, яка є в живому пулі:", sorted(пара) if пара else "жодної")
assert пара, "у пулі стенда нема жодної конфліктної пари — правилу нема на чому спрацювати"

a, b = sorted(пара)
н = []
for k in (a, b):
    с, номер = next((x for x in за_реєстром[k] if x[0] not in [y[0] for y in н]), за_реєстром[k][0])
    н.append((с, номер))
речі = [номер for _с, номер in н]
відп = json.dumps({"версія": "1", "образи": [{"ід": "о1", "речі": речі}]}, ensure_ascii=False)
в = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=відп), ensure_ascii=False)))
зн = [z for z in в["вердикт"]["образи"][0]["знахідки"] if z["правило"] == "K-REG-05"]
print("образ:", н)
print("K-REG-05 у вердикті:", [(z["сила"], z["сила_нп"], z["суть"][:70]) for z in зн])
assert зн and зн[0]["сила_нп"] > 0, в["вердикт"]["образи"][0]["знахідки"]
print("когерентних пар у тому ж образі премійовано:",
      len([z for z in зн if "когерент" in z["суть"]]), "— бонусу правило не дає взагалі")
