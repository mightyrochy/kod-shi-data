# -*- coding: utf-8 -*-
"""Розбір 3/8: який ПАСПОРТ дійшов у пакет рук 1–2 — і чи це паспорт того прогону.

Прогін власника 25.09, розклад 4123: у ПАКЕТ_V1 складання стоїть подія «Як і з чим
носити цю спідницю?», дрес-код smart_casual, ошатність [4,6] і ОДНА закріплена
річ, а `спільне.паспорт` того ж прогону несе подію «похід на концерт» і ДВІ. Проба
кладе поруч мітки часу: коли йшли виклики моделі цього прогону і коли в чаті
зʼявилась репліка з двома фото. Знахідка ділянки 2/8 (`шлях_речі_паспорт_не_той.py`,
PR #344): `спільне.паспорт` і `чат` — стан на момент ВИВАНТАЖЕННЯ, не прогону.
Прогін: python3 проби/шлях_пул_паспорт_прогону.py
"""
import json, os, re
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ФАЙЛ = os.path.join(os.path.dirname(ТУТ), "аудит", "тести", "власник_2026-09-25",
                    "verdykty-0phxvk-2026-09-25-2012.json")
ЧАС = re.compile(r"2026-09-2\d[T ]\d\d:\d\d:\d\d")
д = json.load(open(ФАЙЛ, encoding="utf-8"))
print("файл вивантажено: %s" % д.get("вивантажено"))
for пр in д["прогони"]:
    сп = пр["спільне"]
    руки = [в for в in пр["вердикти"] if str(в.get("рука")) in ("1", "2")]
    викл = ((руки[0].get("етапи") or {}).get("виклики") or []) if руки else []
    текст = ((викл[0].get("запит") or {}) if викл else {}).get("текст") or ""
    if not текст.startswith("{"):
        continue
    пак, п = json.loads(текст), сп.get("паспорт") or {}
    вип, обм = пак.get("випадок") or {}, пак.get("обмеження") or {}
    print("прогін розклад %s (%s), рука %s" % (сп.get("розклад"), сп.get("дата"), руки[0].get("рука")))
    print("  мітки часу самої руки (виклики моделі, вердикт): %s"
          % sorted(set(ЧАС.findall(json.dumps(руки[0], ensure_ascii=False)))))
    print("  мітки часу «чату прогону» у шапці:              %s"
          % sorted(set(ЧАС.findall(json.dumps(сп.get("чат") or [], ensure_ascii=False)))))
    print("  слова жінки у вхід_прогону: %r" % ((сп.get("вхід_прогону") or {}).get("слова") or ""))
    print("  паспорт у ШАПЦІ прогону: подія=%r дрес_код=%r ошатність=%r речей_з_фото=%d"
          % (п.get("подія"), п.get("дрес_код"), п.get("ошатність"), len(п.get("речі_з_фото") or [])))
    print("  паспорт, що ДІЙШОВ у ПАКЕТ_V1: подія=%r дрес_код=%r ошатність=%r закріплених=%d %s"
          % (вип.get("подія"), вип.get("дрес_код"), вип.get("ошатність"),
             len(обм.get("закріплені") or []), обм.get("закріплені") or []))
