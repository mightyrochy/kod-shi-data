# -*- coding: utf-8 -*-
"""Рядок 197 (п.12, кошик В): скільки фраз коду прозою лишилось у діагнозі ПОЗА мовним шаром —
на main, на голові гілки й у робочому дереві. Місця: вирази `ЗБ.діагноз.push(…)`, тіло
`рядкиВиборуСтилісткиП` (рядки «вибір палітри: …») і кидки `throw new Error(…)` поза мостами
(транспорт, стеля виводу, pyodide, полотно, «на фото не…», «жодна рука»). Друкує лічбу
кириличних літералів і перші рядки-порушники. Запуск із теки `джерела`:
`python3 проби/ч8_фрази_діагнозу.py`."""
import re, subprocess
КИР, ЛІТ = re.compile(r"[а-яіїєґА-ЯІЇЄҐ]"), re.compile(r"'((?:\\.|[^'\\])*)'|\"((?:\\.|[^\"\\])*)\"")
СЕР = re.compile(r"HTTP|стелю виводу|pyodide|дзеркало|картинки|полотно|токена|жодна рука|на фото не|не впізнано")
def дужки(т, п=0):                                  # кінець виразу з відкритою дужкою перед п
    г = 1
    while г and п < len(т):
        г += {"(": 1, "[": 1, ")": -1, "]": -1}.get(т[п], 0); п += 1
    return т[:п]
ІД = re.compile(r"===\s*'[^']*'|хто\('[^']*'\)")          # ід у порівнянні й ключ поля — не фраза
def кир(вираз): return [a or b for a, b in ЛІТ.findall(ІД.sub("", вираз)) if КИР.search(a or b)]
def кир_ід(вираз): return [м.group(0) for м in ІД.finditer(вираз) if КИР.search(м.group(0))]
def лічба(т):
    т = re.sub(r"/\*.*?\*/", "", т, flags=re.S)
    діаг = [(dp := дужки(т[м.end():])) and кир(dp) for м in re.finditer(r"ЗБ\.діагноз\.push\(", т)]
    діаг = [л for гр in діаг if гр for л in гр]
    вб = re.search(r"function рядкиВиборуСтилісткиП\(.*?\n\}", т, re.S)
    вибір = кир(вб.group(0)) if вб else []
    кидки = [кир(дужки(т[м.end():])) for м in re.finditer(r"throw new Error\(", т)]
    поза = [л for к in кидки if к and СЕР.search(" ".join(к)) for л in к]
    ід = [л for м in re.finditer(r"ЗБ\.діагноз\.push\(", т) for л in кир_ід(дужки(т[м.end():]))]
    if вб: ід += кир_ід(вб.group(0))
    return (dict(діагноз=len(діаг), вибір_палітри=len(вибір), кидки_поза_мостами=len(поза)),
            діаг + вибір + поза, sorted(set(ід)))
def файл(дж, ім): return (subprocess.run(["git", "show", "%s:джерела/%s" % (дж, ім)], capture_output=True,
                                         text=True).stdout if дж else open(ім, encoding="utf-8").read())
for назва, джерело in (("main", "origin/main"), ("голова", "HEAD"), ("робоче", None)):
    л, фрази, ід = лічба(файл(джерело, "показ.html"))
    print("%-7s %s · разом %d · ід (не фрази): %s"
          % (назва, " · ".join("%s %d" % кв for кв in л.items()), sum(л.values()), ід or "—"))
    for ф in фрази[:3]: print("        «%s»" % ф[:70])
