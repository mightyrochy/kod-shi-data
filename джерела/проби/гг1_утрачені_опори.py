"""ГГ-ОГЛЯД (09.10, рядок 2663): чи доходить утрачена опора до промпту ВИБОРУ (`lost_supports`) — без моделі.
Попередній вердикт: o1 (відлуння сумки #3 до сукні) і o2 (те саме на #7/#8). Ремонт: o1 міняє сумку #3 → #9,
o2 замінено цілком новим o3. Очікувано: o1 — `lost_supports` з відлунням; o3 — порожньо (пара шукається за перетином
складу, `вердикт_моделі.утрачені_опори`); опора o2, що зникла разом з образом, — у `set.lost_supports` з адресою «o2»
(`опори_зниклих_образів`, рядок 2663; доти вибір її не бачив).
Запуск із джерела/: python3 проби/гг1_утрачені_опори.py"""
import json, os, sys
Д = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, Д); os.chdir(Д)
import вердикт_моделі as В, дріт_моделі as ДР, внутрішня_мова as ВМ
луна = lambda r: dict(правило="K-ACC-01", речі=r, заяви=[ВМ.заява("accessory_echoes_accent", slot="bag", accent_slot="dress")])
поп = {"образи": [{"ід": "o1", "речі": ["#1·00", "#2·01", "#3·02"], "опори": [луна(["#2·01", "#3·02"])]},
                  {"ід": "o2", "речі": ["#7·00", "#8·01"], "опори": [луна(["#7·00", "#8·01"])]}]}
нові = [{"ід": "o1", "речі": ["#1·00", "#2·01", "#9·09"]}, {"ід": "o3", "речі": ["#5·00", "#6·01"]}]
утр = В.утрачені_опори(нові, поп)
зниклі = В.опори_зниклих_образів(нові, поп)
дріт = ДР.вердикт({"вердикт": [dict(образ={"ід": о["ід"]}, **({"утрачені_опори": у} if у else {})) for о, у in zip(нові, утр)],
                   **({"набір": {"утрачені_опори": зниклі}} if зниклі else {})}, вибір=True)
for о, в in zip(нові, дріт["verdict"]):
    print("  %s: lost_supports %s" % (о["ід"], json.dumps(в.get("lost_supports") or [], ensure_ascii=False)))
print("  set: lost_supports %s" % json.dumps((дріт.get("set") or {}).get("lost_supports") or [], ensure_ascii=False))
print("  опор попереднього вердикта: 2 · показано вибору як утрачені: %d" % (sum(len(у) for у in утр) + len(зниклі)))
