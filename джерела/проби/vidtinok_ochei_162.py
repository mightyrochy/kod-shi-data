# -*- coding: utf-8 -*-
"""Рядок 162: скільки речей акцентних слотів каталогу несуть тон очей у дузі схеми «тональна» (±півдуги навколо
тону очей) — ДО (точка: lab речі, для кольору-слова це центр вікна) і ПІСЛЯ (`колір_річ.несе_тон`: вікно слова ∩
дуга поза нейтраллю; вимір — точка з допуском виміру). Окремо колір-слово і вимір з фото; шість кольорів очей.
cd джерела && python3 проби/vidtinok_ochei_162.py"""
import sys, os, collections as К
Д = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); os.chdir(Д); sys.path.insert(0, Д)
import feed as Ф, colorspace as cs, колір_річ as КР, палітра_схеми as ПС
АКЦ = ("сумка", "взуття", "прикраси", "шарф", "пояс", "головний_убір")
кат = [r for r in Ф._база_прогону(Ф.каталог_на_диску("каталог_повний.xml"), 0, "стенд_кеш_кольорів.json")["каталог"]
       if r.get("слот") in АКЦ]
ОЧІ = {"стенд #759087": "#759087", "блакитні #6a8fb3": "#6a8fb3", "карі #5a3c22": "#5a3c22",
       "сірі #7d8790": "#7d8790", "зелені #5f7a4a": "#5f7a4a", "горіхові #7a6a3e": "#7a6a3e"}
def до(r, д):                               # колишній `міст_пакет._несе_колір`: точка lab у дузі, не нейтраль
    lab = r.get("lab")
    if not lab or КР.нейтраль(tuple(lab)): return False
    return КР._на_дузі(cs.lch(tuple(lab))[2] % 360, д)
пів = getattr(ПС, "ПІВДУГА_ТОНАЛЬНОЇ", 12.0)
print("речей акцентних слотів: %d · колір-слово %d · вимір %d · півдуга ±%.0f°" % (
    len(кат), sum(1 for r in кат if КР.не_вимір(r)), sum(1 for r in кат if not КР.не_вимір(r)), пів))
for назва, hx_ in ОЧІ.items():
    h = cs.lch(cs.hx(hx_))[2]; д = ПС._дуга(h, пів)
    а = К.Counter("слово" if КР.не_вимір(r) else "вимір" for r in кат if до(r, д))
    б = К.Counter(КР.несе_тон(r, д) for r in кат); б.pop(None, None)
    сл = К.Counter(КР.не_вимір(r).get("слово") for r in кат if КР.несе_тон(r, д) == "слово")
    print("%-18s h %5.1f дуга %s · ДО слово %3d вимір %3d · ПІСЛЯ слово %4d вимір %3d · слова: %s" % (
        назва, h, д, а["слово"], а["вимір"], б["слово"], б["вимір"], dict(сл.most_common(4))))
