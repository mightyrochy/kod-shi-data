# -*- coding: utf-8 -*-
"""K-P0-01 (посадка — ГЕЙТ, не критерій з вагою) — твердження переїхало з
коментаря в ключ ранжування.

ДО ПРАВКИ: блок у `composer._оцінити` має заголовок «ПОСАДКА — ГЕЙТ, НЕ КРИТЕРІЙ З
ВАГОЮ» і дослівно обіцяє «між двома блокованими блок посадки важить першим (ключ
сортування нижче)». Ключ нижче брав `x["блокує"]` — ЛІЧБУ блокерів будь-якого
роду. Отже комбінація з ОДНИМ блоком посадки ставала попереду комбінації з ДВОМА
композиційними: «не сидить» вигравало в «сидить, але два зауваження». Число
`_блок_посадки` рахувалось у `_оцінити`, лежало в кожному рядку `оцінені` — і не
читав його ніхто.
ПІСЛЯ: `_ключ_ранжування` читає його ПЕРШИМ.
І ДРУГА ПОЛОВИНА, ЯКУ ПРОБА ТЕЖ ДРУКУЄ: гейт порожній, і це рішення КОРПУСУ, не
недогляд. Жодне правило шару посадки не має регістру «гейт» — K-FIT-01 корпус
прямо забороняє підвищувати («must not be promoted to a hard gate on this
evidence»), решта стоїть реплікою за дефолтом. Тому порядок тепер правильний і
мовчазний; оживить його не правка тут, а мірки виробу у фіді."""
import sys, pathlib, json, random
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, composer as КМ, fit as ПС, silhouette as СЛ

не_сидить = dict(блок_посадки=1, блокує=1, сума_сил=0.0, речі=[])
сидить = dict(блок_посадки=0, блокує=5, сума_сил=9.9, речі=[])
print("«не сидить» (1 блок) проти «сидить» (5 блоків, сума 9.9) → не сидить позаду:",
      КМ._ключ_ранжування(не_сидить) > КМ._ключ_ранжування(сидить))
assert КМ._ключ_ранжування(не_сидить) > КМ._ключ_ранжування(сидить)

# Регістр питається ТИМ САМИМ шляхом, яким правило емітується, — через `_зн`
# свого модуля: інакше стеля тіру (усі десять констант шару — T3) не застосується,
# і відповідь буде про таблицю, а не про вихід.
ПОСАДКА = (("K-FIT-01", ПС), ("K-FIT-03", ПС), ("K-FIT-06", ПС), ("K-BOD-02", ПС),
           ("K-BOD-05", ПС), ("K-SHO-02", ПС), ("K-CUT-00", ПС),
           ("K-SIL-01", СЛ), ("K-SIL-02", СЛ), ("K-SIL-03", СЛ))
гейтів = [п for п, м in ПОСАДКА
          if м._зн(п, "strong", "проба", ["x"], "проба").get("блокує")]
print("правил шару посадки %d · блокують на найвищій силі %d %s"
      % (len(ПОСАДКА), len(гейтів), гейтів or "— гейт порожній за рішенням корпусу: "
         "K-FIT-01 тема-1:704 забороняє підвищувати, решта під стелею тіру T3"))

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
пак = [p for p in B._КЕШ_ПАКЕТА.values() if p.get("кандидати")][0]
пул = {с: [r["id"] for r in п] for с, п in пак["кандидати"].items() if п}
rnd, зн_всього, блоків = random.Random(7), 0, 0
for _ in range(6):
    ід = [rnd.choice(пул["сукня"]), rnd.choice(пул["взуття"]), rnd.choice(пул["сумка"])]
    вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
    о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
    блоків += len(о.get("блокує") or [])
print("6 образів живого каталогу: блокерів усього %d — гейт посадки не спрацьовує "
      "жодного разу, бо `верх_см/низ_см` беруть із дефолту слота" % блоків)
