"""Спільне джерело: суд усіх правил, учасники, межі й явний вибір, без сум."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import пропозиція_заміни as П


def головна():
    """Друкує факти контракту на двох речах із залежною спільною зміною."""
    а, б, в, г = [dict(id=і, слот=с) for і, с in (("а", "верх"), ("б", "шар"), ("в", "верх"), ("г", "шар"))]
    def зн(правило, річ, вага=0.5, **поля):
        """Утворює знахідку із правилом і дійсним учасником."""
        return dict(правило=правило, суть="вимір", речі=[річ], сила_нп=вага, **поля)
    початок = dict(знахідки=[зн("K-CLR-02", "а")])
    межі = {р["id"]: р for р in (а, б, в, г)}
    виклики = []
    def суд(склад):
        """Переносить зауваження на іншу річ, доки обидві не змінені."""
        ід = [р["id"] for р in склад]; виклики.append(ід)
        return dict(знахідки=[] if ід == ["в", "г"] else [зн("K-CLR-02", "б")])
    def проба(кандидати, вибір=(), суддя=суд, пул=межі):
        """Викликає той самий контракт із різними межами чи судом."""
        return П.перевірити([а, б], початок["знахідки"], кандидати, пул, вибір, суддя, початок)
    assert not проба([[в, б]])["заміни"]
    спільна = проба(П.варіанти([а, б], {"а": [в], "б": [г]}))
    assert len(спільна["заміни"]) == 2 and спільна["вердикт"]["знахідки"] == []
    for знахідки in ([зн("інше", "в")], [зн("K-CLR-02", "в", 0, сила="утримано")], [зн("інше", "в", 0, сила="утримано")]):
        assert not проба([[в, г]], суддя=lambda _: dict(знахідки=знахідки))["заміни"]
    до = len(виклики)
    assert not проба([[в, г]], вибір=["а"])["заміни"]
    assert not проба([[в, г]], пул={})["заміни"]
    assert not проба([[dict(в, колір="чуже"), г]])["заміни"]
    assert len(виклики) == до and а == dict(id="а", слот="верх")
    print("Перенесення: відмова; спільна: 2 речі; інше правило й брак входу: відмова; межі та вибір: збережено")


if __name__ == "__main__":
    головна()
