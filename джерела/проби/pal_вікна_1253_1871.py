"""Рядки 1253, 1871: K-PAL-12 і K-PAL-08 на образах із кольором зі СЛОВА (вікно лексикону, рядок 141).
Стенд руки 1 під statement, 3000 образів пулу (верх+низ або сукня, взуття, сумка, сід 7) — частки
«вирок / без входу / мовчить» обох правил на рівнях контрасту; і де доїжджає «без входу»: K-PAL-08 —
пункт P4 чекліста палітри, K-PAL-12 — P9 (до правки рядка 1253 пункту не було). Моделі не кличе.
Запуск: cd джерела && python3 проби/pal_вікна_1253_1871.py"""
import collections, json, random, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import суд_від_моделі as СВМ, колір_образу as КО, bridge as B
вх, r, кат, спец = ПВ.стенд(гілка=0, намір="statement")
П, к, rnd = спец["палітра_практична"], r["кандидати"], random.Random(7)
def образ():
    о = [rnd.choice(к["сукня"])] if rnd.random() < 0.4 else [rnd.choice(к["верх"]), rnd.choice(к["низ"])]
    return [dict(id=x["id"], слот=кат[x["id"]]["слот"]) for x in о + [rnd.choice(к["взуття"]), rnd.choice(к["сумка"])]]
образи = [образ() for _ in range(3000)]
print("контраст стенда «%s»; образів зі словом %d з %d" % (П.get("контраст_рівень"),
      sum(1 for о in образи if any(КО.не_вимір(кат[x["id"]]) for x in о)), len(образи)))
for рів in ("низький", "високий"):
    c = collections.Counter()
    for о in образи:
        зн = СВМ.палітра_образу(о, {"_палітра": П, "_контраст": рів}, кат)
        for пр in ("K-PAL-08", "K-PAL-12"):
            z = [x for x in зн if x.get("правило") == пр]
            c[(пр, "без входу" if any(x.get("без_входу") for x in z) else "вирок" if z else "мовчить")] += 1
    for пр in ("K-PAL-08", "K-PAL-12"):
        в, б, м = c[(пр, "вирок")], c[(пр, "без входу")], c[(пр, "мовчить")]
        print("контраст %-8s %s: вирок %4d · без входу %4d · мовчить %4d · без входу серед суджених %d %%"
              % (рів, пр, в, б, м, round(100 * б / max(1, в + б))))
# ЖИВИЙ ШЛЯХ (`від_моделі`): образ гучного жовтого верху з трьома словами по обидва боки порога
ід = ["ж-01680@vovk.com", "ж-06393@sunwin-store.com", "ж-10151@kasandra.ua", "ж-07779@welfare.ua"]
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
z = [x.get("сила") for x in вм["вердикт"]["образи"][0]["знахідки"] if x.get("правило") == "K-PAL-12"]
п = [(x["пункт"], x["стан"], (x.get("бракує") or "")[:70]) for x in (вм.get("чеклісти") or {}).get("палітра") or []
     if "K-PAL-12" in x.get("правила", ()) or x["пункт"] == "P4"]
print("від_моделі (жовтий верх + перлинний, молочний, білий зі слів): K-PAL-12 %s · чекліст %s" % (z, п))
