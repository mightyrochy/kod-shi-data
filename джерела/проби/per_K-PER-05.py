# -*- coding: utf-8 -*-
"""K-PER-05 (сенсорне обмеження — тверде й постійне) — власний приклад корпусу
був невидимий на 98.4 %.

КОРПУС називає рівно два приклади сенсорного обмеження: «will not wear wool
against skin, will not wear heels», FORCE hard «on the person's authority alone».
ДО ПРАВКИ: `жорстке_ні_фільтр` шукав підрядок у десяти ТЕКСТОВИХ полях речі, а
каблук у картці не слово, а виведений атрибут (`feed.взуттєві_атрибути` віддає
`каблук`, `каблук_см`, `каблук_словами`). Виміряно на `каталог_повний.xml`: із
1 898 пар пакета 1 005 справді на каблуку, і фільтр ловив «каблук» на 0 із них,
«підбор» — на 16. Жінка, яка сказала «не ношу підбори», далі діставала човники.
ПІСЛЯ: сенсорне обмеження ловиться ПРЕДИКАТОМ над виведеним полем.
І ОДНА ПАСТКА, ЯКУ ПРОБА ТЕЖ ДРУКУЄ: `каблук_словами` несе «БЕЗ каблука» й
«каблук НЕ оголошений» на 1 841 картці з 1 898 — підрядковий пошук за ним
відкидав би УСЕ взуття, зокрема пласке, тобто робив би протилежне до сказаного."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, profile as PR

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
взут = [c for c in кат if c.get("слот") == "взуття"]
на_каблуку = [c for c in взут if c.get("каблук") is True or (c.get("каблук_см") or 0) > 0]
словами = [c for c in взут if "каблук" in str(c.get("каблук_словами") or "")]
print("взуття в пакеті %d · справді на каблуку %d · слово «каблук» у полі `каблук_словами` %d"
      % (len(взут), len(на_каблуку), len(словами)))
for сл in (["каблук"], ["не ношу підбори"], ["шпильки"]):
    _, відк = PR.жорстке_ні_фільтр(взут, сл)
    print("  жорстке «ні» %-18s → відкинуто %d" % (str(сл), len(відк)))
    assert len(відк) == len(на_каблуку), "сенсорне обмеження мусить ловити рівно каблучні пари"
# пласка пара під тим самим «ні» лишається: правило не ловить усе взуття підряд
пласка = next(c for c in взут if c not in на_каблуку)
_, відк = PR.жорстке_ні_фільтр([пласка], ["каблук"])
print("пласка пара «%s» під «не ношу каблук»: %s"
      % (пласка["назва"][:34], "відкинуто — ПОМИЛКА" if відк else "лишається (правильно)"))
assert not відк
# і воно доїжджає гейтом у вердикт
взут_каблук = на_каблуку[0]
сук = next(c for c in кат if c.get("слот") == "сукня")
вм = json.loads(B.виклик("від_моделі", json.dumps(
    dict(вх, жорстке_ні=["каблук"], ід=[сук["id"], взут_каблук["id"]]), ensure_ascii=False)))
бл = [x for x in (вм.get("блокує") or []) if "жорстк" in str(x)]
print("блокерів «жорстке ні» на виході: %d — %s" % (len(бл), str(бл[:1])[:96]))
assert бл, "особиста межа мусить блокувати образ, а не промовлятись"
