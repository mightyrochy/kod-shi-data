"""М-2, вада 2: ЧИ ДОХОДИТЬ «unknown» ДО НЕЇ ЯК ЇЇ СЛОВА. Усі збережені відповіді перекладача
сценарію з живого прогону 26.09 (`аудит/тести/сирі_2026-09-26/*.tar.gz`: MamayLM, Lapa і модель
без імені — фрази й питання; прогін для звіту й проба 2 — репліки сценарію власника) йдуть тим
самим шляхом, що в продукті: `прийняти_вхід` → `паспорт_з_шару` → рядок випадку моделям
(`паспорт_рядком`, його бачать усі чотири руки) і їй (`паспорт_рядком_людині`). Друкує, скільки
відповідей несуть «невідомо» у вільному тексті внутрішньої мови (подія, решта, питання, настрій,
назва речі) і скільки з них доїхали до рядків як її слова. Та сама проба на main і на гілці.
Запуск із `джерела`: python3 проби/шлях_шар_невідомо.py"""
import sys, os, re, glob, tarfile, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import мовний_шар as МШ, паспорт_нагоди as ПН, внутрішня_мова as ВМ


def відповіді():
    """(файл, її слова, сира відповідь) кожного перекладу сценарію зі збережених архівів."""
    for тар in sorted(glob.glob("../аудит/тести/сирі_2026-09-26/*.tar.gz")):
        with tarfile.open(тар) as т:
            for ч in т.getmembers():
                с = т.extractfile(ч).read().decode("utf-8").replace("\r\n", "\n") if ч.isfile() else ""
                if "слова жінки про її вихід" in с and "── ВІДПОВІДЬ" in с:
                    слова = re.split(r"\n\n(?:КОНТЕКСТ:|── ВІДПОВІДЬ)", с.split("\nСЛОВА:\n", 1)[1])[0].strip()
                    yield ч.name, слова, с.split("── ВІДПОВІДЬ", 1)[1].split("──\n", 1)[1]


вільні = lambda x: ([x["free_text"]] if isinstance(x, dict) and "free_text" in x else [] if not isinstance(x, (dict, list))
                    else [т for у in (x.values() if isinstance(x, dict) else x) for т in вільні(у)])
НЕВІД = re.compile(r"\b(?:unknown|null|none)\b|невідомо", re.I)
всього = у_вн = у_рядку = 0
for ім, слова, сире in відповіді():
    вн = МШ.прийняти_вхід("scenario", сире)["внутрішня"]
    п = МШ.паспорт_з_шару(вн, {}, None, None, слова_ходу=слова)["паспорт"]
    рядки = ПН.паспорт_рядком(п) + " | " + ПН.паспорт_рядком_людині(п)
    всього += 1
    у_вн += any(ВМ.невідомо(str(т)) for т in вільні(вн))
    if НЕВІД.search(рядки):
        у_рядку += 1
        print("«%s» → %s" % (слова[:40], "; ".join(sorted(set(re.findall(r"[^.|]*(?:unknown|null|невідомо)[^.|]*", рядки, re.I))))[:150]))
print("відповідей перекладача сценарію: %d · з «невідомо» як вільним текстом у внутрішній мові: %d · "
      "з «невідомо» в рядку випадку моделям чи їй: %d" % (всього, у_вн, у_рядку))
