"""Рядок 6979: база a-line за кодом виду, а не за словом крою.
Запуск: cd джерела && python3 проби/база_контуру_6979.py
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import силует_крої as С

ширина = {"плечі": 40, "груди": 38, "талія": 28, "стегна": 40}.get
до = С.ширина_крою("a-line", "груди", ширина)[0] / ширина("груди")
жилет = С.ширина_крою("a-line", "груди", ширина, код_виду="vest")[0] / ширина("груди")
сукня = С.ширина_крою("a-line", "груди", ширина, код_виду="dress_generic")[0] / ширина("груди")
print("над талією: %.3f -> жилет %.3f; сукня %.3f -> %.3f" % (до, жилет, до, сукня))
assert round(до, 3) == 1.007 and round(жилет, 3) == 1.020 and сукня == до
