# -*- coding: utf-8 -*-
"""Скільки знімків її речей доїхало до кожного виклику кожної руки.

Фото закріплених речей збирає `показ.фотоЗакріпленихП` (показ.html:4484) і дає
його ЛИШЕ викликам складання/повтору/перепису; ні ремонт, ні вибір його не
бачать. Лічбу пише `запамʼятатиЗапит` (7979) — це число блоків-зображень."""
import json, os
ТЕКА = os.path.join(os.path.dirname(__file__), "..", "..", "аудит", "тести", "власник_2026-09-25")
for ім in ("verdykty-0phxvk-2026-09-25-2012.json",):
    d = json.load(open(os.path.join(ТЕКА, ім), encoding="utf-8"))
    for п in d["прогони"]:
        закр = [р for р in ((п["спільне"].get("паспорт") or {}).get("речі_з_фото") or [])
                if р.get("закріплена") and р.get("фото")]
        if not закр:
            continue
        print("прогін %s · закріплених речей із фото: %d" % (п["спільне"].get("розклад"), len(закр)))
        for в in п["вердикти"]:
            викл = (в.get("етапи") or {}).get("виклики") or []
            if not викл:
                print("   рука %s: етапів викликів у файлі нема (викликів=%s)" % (в["рука"], в.get("викликів")))
                continue
            рядки = ["%s:%s" % (((c.get("запит") or {}).get("чого") or "?").split(" ")[0][:14],
                                (c.get("запит") or {}).get("фото")) for c in викл]
            складання = [c for c in викл if "складання" in ((c.get("запит") or {}).get("чого") or "")]
            ф = (складання[0].get("запит") or {}).get("фото") if складання else None
            print("   рука %s | складання отримало %s із %d знімків | усі виклики: %s"
                  % (в["рука"], ф, len(закр), ", ".join(рядки)))
