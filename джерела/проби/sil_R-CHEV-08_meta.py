# -*- coding: utf-8 -*-
"""R-CHEV-08 · мета доїжджає до форми (рядок 105): `python3 проби/sil_R-CHEV-08_meta.py`.

Профіль стенда, повний перебір кроїв каталогу верх × низ (як у sil_K-SIL-01) плюс пара
з виміряним подолом, де виходить K-SIL-01. Той самий `силует_суд.перевірити` за метою
«лестити» і «приховати»: скільки знахідок, скільки з них несуть напрям (ремонт / запит
у каталог / суть без «напряму нема») поза K-CUT-00 і «нижче мінімуму» (дефект за
будь-якої мети), регістри, `сила_нп` — і приклад того, що бачить модель, до/після."""
import sys, pathlib, json, collections
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import feed as Ф, bridge as B, outfit as O, silhouette as СЛ, composer as КМ

вх = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml"); вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
F, T, _зр, _kw = B._збірка(вх)
за = collections.defaultdict(list)
for c in B.каталог_останнього_пакета():
    к = O.крій_речі(c)
    if к: за[(c.get("слот"), к)].append(c)
пари = [[КМ._у_річ(dict(за[в][0]), "верх", T), КМ._у_річ(dict(за[н][0]), "низ", T)]
        for в in за if в[0] == "верх" for н in за if н[0] == "низ"]
р1, р2 = КМ._у_річ(dict(за[("верх", "oversized")][0]), "верх", T), КМ._у_річ(dict(за[("низ", "full")][0]), "низ", T)
р1["низ_см"] = р2["верх_см"] = T["висоти"]["талія"]; пари.append([р1, р2])   # подоли ВИМІРЯНІ
судиться = lambda z: z["правило"] != "K-CUT-00" and "нижче мінімуму" not in z["суть"]
напрям = lambda z: bool(z.get("ремонт") or z.get("запит_у_каталог")) or "напряму нема" not in z["суть"]
вих = {}
for мета in ("лестити", "приховати"):
    зн = вих[мета] = [z for п in пари for z in СЛ.перевірити(T, п, intent="conventional", мета=мета)]
    print("мета «%s»: пар %d · знахідок %d · судиться за метою %d · з них із напрямом %d · %s · регістри %s"
          % (мета, len(пари), len(зн), sum(map(судиться, зн)), sum(1 for z in зн if судиться(z) and напрям(z)),
             dict(collections.Counter(z["правило"] for z in зн)), dict(collections.Counter(z["регістр"] for z in зн))))
сили = [(a["правило"], a["сила"], a["регістр"], a["сила_нп"]) == (b["правило"], b["сила"], b["регістр"], b["сила_нп"])
        for a, b in zip(вих["лестити"], вих["приховати"])]
print("та сама лічба, правило, сила, регістр і сила_нп у кожній парі:", all(сили), len(сили))
a, b = next((a, b) for a, b in zip(вих["лестити"], вих["приховати"]) if судиться(a))
print("ДО   :", a["суть"][:100], "· ремонт:", str(a.get("ремонт"))[:64])
print("ПІСЛЯ:", b["суть"][:100], "· ремонт:", b.get("ремонт"), "· запит:", b.get("запит_у_каталог"))
assert all(сили) and not [z for z in вих["приховати"] if судиться(z) and напрям(z)]
