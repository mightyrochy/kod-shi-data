# Рядок 5657: ФАКТ на повторному збиранні тих самих карток крамниці (знімки сторінок лежать у теці, адреси — у json
# {крамниця: [адреси]}): чужий текст у складі, сума ≠ 100, «схожі» в описі, шаблонні початки опису, `матеріал_родина`.
# Слова тут читає ПРОБА, не код. Запуск: python3 каталог_проблеми_в_перезбір.py <тека жниварки> <тека знімків> <url.json>
import collections as C, hashlib, importlib, json, os, re, sys
sys.path.insert(0, os.path.abspath(sys.argv[1]))
ж = importlib.import_module("жниварка")
ЧУЖЕ = re.compile(r"[а-яіїє][А-ЯІЇЄ][а-яіїє]{3,}|(?i:дивіться також|правила|таблиц|доставк|відгук|розмір)")
СХОЖІ = re.compile(r"схожі товари|вам також|з цим товаром|ви переглядали|дивіться також", re.I)   # без «рекомендуємо»: це слово самого опису
відс = lambda с: [int(x) for x in re.findall(r"(\d{1,3})\s*%", с)]
сума = lambda в: any(sum(в[:i]) == 100 for i in range(1, len(в) + 1))
for крамниця, адреси in json.load(open(sys.argv[3], encoding="utf-8")).items():
    р = C.Counter(); початки = C.Counter()
    for u in адреси:
        шлях = os.path.join(sys.argv[2], hashlib.sha1(u.encode()).hexdigest()[:16] + ".html")
        if not os.path.exists(шлях):
            continue
        ф = ж.факти_з_картки(open(шлях, encoding="utf-8").read(), u, *([ж.рецепт_селекторів(крамниця)] if hasattr(ж, "рецепт_селекторів") else []))
        з = ж.канонічний_запис(ф, {"домен": крамниця, "платформа": None}, "картка")
        с, оп = з.get("склад") or "", з.get("опис") or ""
        р["карток"] += 1; р["зі складом"] += bool(с); р["склад без %"] += bool(с and not відс(с))
        р["склад з чужим текстом"] += bool(ЧУЖЕ.search(с)); р["сума ≠ 100"] += bool(відс(с) and not сума(відс(с)))
        р["склад непевний"] += bool(з.get("склад_непевний")); р["з описом"] += bool(оп)
        р["«схожі» в описі"] += bool(СХОЖІ.search(оп)); р["HTML у описі"] += bool(re.search(r"&#?\w+;|</?[a-z]+[ />]", оп)); р["з матеріал_родина"] += "матеріал_родина" in з
        початки[оп[:120]] += bool(оп)
    р["шаблонних початків (≥ 3 карток)"] = sum(1 for k, v in початки.items() if v >= 3 and k)
    р["найбільший однаковий початок, карток"] = max([v for k, v in початки.items() if k] or [0])
    print("%-22s %s" % (крамниця, dict(р)))
