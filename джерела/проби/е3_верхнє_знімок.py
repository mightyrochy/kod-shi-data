"""Знімок ваги кожної знахідки `без_входу`, `ремонтопридатність` і `догляд` (верхнє_суд,
верхнє_догляд) на повному каталозі й граничних входах; другий аргумент — коміт ДО.

ДО завантажує з git саме два змінені модулі; робочих файлів не підміняє. Кеш каталогу —
`$TMP/е3_каталог.json.gz` (той самий, що в погодній звірці)."""
import collections, gzip, importlib.abc, importlib.util, json, linecache, os, pathlib, subprocess, sys
КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРІНЬ / 'джерела'))
МОДУЛІ = ('верхнє_суд', 'верхнє_догляд')


def база(коміт):
    """Підставити код двох модулів із коміту під час імпорту."""
    class База(importlib.abc.MetaPathFinder, importlib.abc.Loader):
        def find_spec(self, fullname, path=None, target=None):
            if fullname in МОДУЛІ:
                return importlib.util.spec_from_loader(fullname, self)

        def create_module(self, spec):
            return None

        def exec_module(self, module):
            шлях = 'джерела/' + module.__name__ + '.py'
            текст = subprocess.check_output(['git', 'show', коміт + ':' + шлях], cwd=КОРІНЬ).decode('utf-8')
            шлях = str(КОРІНЬ / шлях)
            linecache.cache[шлях] = (len(текст), None, текст.splitlines(True), шлях)
            module.__file__ = шлях
            exec(compile(текст, шлях, 'exec'), module.__dict__)
    sys.meta_path.insert(0, База())


def каталог():
    """Повний каталог без фото; кеш у TMP."""
    кеш = pathlib.Path(os.environ.get('TMP', '/tmp')) / 'е3_каталог.json.gz'
    if not кеш.exists():
        import feed as Ф
        к = Ф.база_прогону(Ф.каталог_на_диску('каталог_повний.xml'), ліміт_фото=0)['каталог']
        with gzip.open(кеш, 'wt', encoding='utf-8') as ф:
            json.dump(к, ф, ensure_ascii=False)
    with gzip.open(кеш, 'rt', encoding='utf-8') as ф:
        return json.load(ф)


def набори(кат, С, ПС):
    """(назва, функція, args, kwargs): кожен верхній шар і кожна пара верх × жакет."""
    верхні = [р for р in кат if р.get('слот') == 'верхній_шар']
    жакети = [р for р in кат if р.get('слот') == 'верх' and р.get('тип') in ('блейзер', 'костюм')]
    вх = json.loads((КОРІНЬ / 'джерела/стенд_вх.json').read_text(encoding='utf-8'))
    тіла = [('без_тіла', None), ('стенд', ПС.тіло(вх['зріст'], вх['обхвати']))]
    # Граничні: склад не оголошено (K-OUT-44 питання), замша й нубук (K-OUT-45), fill power (K-OUT-15).
    гран = [dict(id='г-без-складу', слот='верхній_шар', назва='пальто'),
            dict(id='г-замша', слот='верхній_шар', назва='дублянка', матеріал='замша', матеріал_верху='замша'),
            dict(id='г-нубук', слот='верхній_шар', назва='куртка', матеріал='нубук'),
            dict(id='г-вовна', слот='верхній_шар', назва='пальто', матеріал='вовна', вовна_частка=0.7),
            dict(id='г-шкіра', слот='верхній_шар', назва='куртка', матеріал='шкіра'),
            dict(id='г-синтетика', слот='верхній_шар', назва='куртка', матеріал='поліестер'),
            dict(id='г-fp', слот='верхній_шар', назва='пуховик', fill_power=800)]
    опади = (None, 'дощ') + tuple(С.СОЛЬОВІ_ОПАДИ)
    for р in гран + верхні:
        yield str(р['id']), 'без_входу', [[р]], {}
        for смуга in С.СМУГИ_ПОГОДИ:
            for о in опади:
                for реаг in (None, True, 'ні'):
                    yield '%s@%s@%s@%s' % (р['id'], смуга, о, реаг), 'догляд', [[р]], dict(
                        реагенти=реаг, смуга_погоди=смуга, опади=о)
    # Граничні пари K-OUT-05: край виміряний («річ») чи зі слова — жакет визирає, межа похибки, вкрито.
    пари = []
    for дж in ('річ', 'слово'):
        for в_см, ж_см in ((90.0, 60.0), (80.0, 70.0), (62.0, 60.0), (60.0, 61.0), (40.0, 90.0)):
            пари.append((dict(id='г-пальто-%s-%g' % (дж, в_см), слот='верхній_шар', назва='пальто',
                              низ_см=в_см, край_джерело=дж),
                         dict(id='г-жакет-%s-%g' % (дж, ж_см), слот='верх', тип='блейзер', назва='блейзер',
                              низ_см=ж_см, край_джерело=дж)))
    for в, ж in пари:
        for ім, т in тіла:
            yield '%s+%s@%s' % (в['id'], ж['id'], ім), 'ремонтопридатність', [[в, ж]], dict(тіло=т)
    for в in верхні:
        for ж in жакети:
            for ім, т in тіла:
                yield '%s+%s@%s' % (в['id'], ж['id'], ім), 'ремонтопридатність', [[в, ж]], dict(тіло=т)


def main():
    """Записати сиру й обмежену вагу; підсумок за правилом і функцією."""
    if len(sys.argv) > 2:
        база(sys.argv[2])
    import верхнє_суд as ВС, верхнє_догляд as ВД
    import fit as ПС, сценарій as С, trace as Т
    from реєстр_сила import обмежити_вагу
    assert all(м in sys.modules and sys.modules[м].__file__ for м in МОДУЛІ)
    функції = dict(без_входу=ВС.без_входу, ремонтопридатність=ВС.ремонтопридатність, догляд=ВД.догляд)
    кат = каталог()
    вих, підсумок, сліди = [], collections.Counter(), collections.Counter()
    for назва, ф, args, kwargs in набори(кат, С, ПС):
        Т.почати()
        for з in функції[ф](*args, **kwargs):
            вих.append([назва, ф, з['правило'], з.get('суть'), з.get('речі'), з.get('сила'),
                        з.get('блокує'), з.get('сила_нп'), обмежити_вагу([dict(з)])[0].get('сила_нп')])
            підсумок[ф, з['правило'], з.get('сила')] += 1
        for з in Т.ЗАПИСИ:
            if isinstance(з, dict) and з.get('правило') in ('K-OUT-44', 'K-OUT-45'):
                сліди[ф, з.get('правило'), з.get('сила')] += 1
    with gzip.open(sys.argv[1], 'wt', encoding='utf-8') as ф:
        json.dump(вих, ф, ensure_ascii=False)
    print('каталог', len(кат), 'знахідок', len(вих))
    for к, v in sorted(підсумок.items(), key=str):
        print(' ', *к, v)
    print('сліди K-OUT-44/45:', dict(сліди))


if __name__ == '__main__':
    main()
