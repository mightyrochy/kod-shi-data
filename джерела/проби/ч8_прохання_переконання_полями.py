print("ВИПАДОК руки 1: прохання_взуття=%s · переконання=%s · her_words=%s"
      % (випадок.get("прохання_взуття"), json.dumps(випадок.get("переконання"), ensure_ascii=False),
         json.dumps(випадок.get("вимоги_людини"), ensure_ascii=False)))
print("промпт руки 1 (дріт): shoe_request %s · beliefs %s · «%s» %s · «%s» %s"
      % ('"shoe_request"' in промпт, '"beliefs"' in промпт,
         префікси[0].strip(), префікси[0] in промпт, префікси[1].strip(), префікси[1] in промпт))
print("текст вимог цілий: руки 3–4 несуть прохання %s і переконання %s · фільтр взуття читає «%s»"
      % (префікси[0] in вимоги34, префікси[1] in вимоги34, КБ.прохання(вимоги34)))
