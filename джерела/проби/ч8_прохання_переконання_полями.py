import json, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import feed as Ф, bridge as B, каблук as КБ, пакет_моделі as ПМ

вх = json.load(open(pathlib.Path(__file__).resolve().parent.parent / "стенд_вх.json", encoding="utf-8"))
вх["каталог"], вх["гілка"] = Ф.каталог_на_диску("каталог_повний.xml"), 0
вх["паспорт"] = {"перекладено_шаром": True, "подія": "вечеря з друзями",
                 "вето": {"типи": ["підбори"]}, "слова": "хочу щось тепле",
                 "переконання": ["горизонтальна смужка мене повнить"]}
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
випадок = ((r.get("пакети") or {}).get("1") or {}).get("випадок") or {}
