"""Сила емісії без мертвих голосів; межа капелюха читається з реєстру."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import fit
import accessory as А
import outer
import реєстр_правил as Р

def мірило():
    """Звіряє стелі сил і обидва боки змінюваного допуску капелюха."""
    for модуль, правило, сила in ((fit, "K-FIT-04", "strong"),
            (А, "K-WEA-05", "default"), (А, "K-WEA-06", "default"),
            (outer, "K-OUT-41", "strong")):
        з = Р.зн(правило, "strong", "вимір", ["річ"], "вимір", reg=модуль.РЕЄСТР)
        print(правило, з["сила"])
        assert з["сила"] == сила, з
    assert Р.стеля_сили("K-COL-05") == "soft"
    assert Р.стеля_сили("K-CRA-02") is None
    сп = А.АКСЕСУАР_ВИМІР["головний_убір"]
    допуск = А.C["голова_допуск_см"]
    try:
        for межа in (допуск, допуск + 1):
            А.C["голова_допуск_см"] = межа
            for розб in (межа, межа + 0.25):
                провал, з = А._ворота_однієї("головний_убір", сп,
                    {"обхват_голови_см": 56 + розб}, "капелюх", {"голова_см": 56})
                print("K-HAT-01", межа, розб, провал)
                assert провал == (розб > межа), з
                if з:
                    assert з["поріг"]["значення"] == межа, з
                    assert з["сила"] == "strong", з
    finally:
        А.C["голова_допуск_см"] = допуск

if __name__ == "__main__":
    мірило()
