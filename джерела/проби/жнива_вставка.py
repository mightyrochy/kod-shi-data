"""Друкує, чи пряма відповідь зору переживає розбір без вигаданої вставки."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from жнива_розбір import нормалізувати


def main():
    """Звіряє слово й частку, явне null, відсутнє поле та хибні форми."""
    вставка = {"слово": "чорний", "частка": 0.137}
    assert нормалізувати({"вставка": вставка}, "прикраса")["вставка"] == вставка
    assert нормалізувати({"вставка": None}, "прикраса")["вставка"] is None
    assert "вставка" not in нормалізувати({"метал": "золотистий"}, "прикраса")
    assert "вставка" not in нормалізувати({"вставка": вставка}, "одяг")
    хибні = ["чорний", {}, {"слово": "чорний"}, {"слово": "не колір", "частка": .2}]
    хибні += [{"слово": "чорний", "частка": ч} for ч in [-.1, 1.1, True, "0.2", float("nan"), float("inf")]]
    for значення in хибні:
        try:
            нормалізувати({"вставка": значення}, "прикраса")
        except ValueError:
            continue
        raise AssertionError("хибну форму прийнято: %r" % значення)
    print("вставка: слово й частка збережені; null явне; пропуск не став null; хибних форм відхилено:", len(хибні))


if __name__ == "__main__":
    main()
