"""Друкує завершення палітри й відмови для непідтверджених режимів (7680)."""
import importlib.util
import pathlib

опис = importlib.util.spec_from_file_location('живі_до', pathlib.Path(__file__).resolve().parents[2] / 'аудит/проби/живі_до.py')
м = importlib.util.module_from_spec(опис)
опис.loader.exec_module(м)
екран = '1б. екран «Палітра» за 1 с\n'
вибір = '   П-7 вибір стилістки на екрані: {}\n'
кінець = '1б · написів «без пояснення словами» на екрані «Палітра»: 0 · рядків біля схем 6 · нота: "порада"'
палітра = екран + вибір + кінець
for лог in ['', 'показ ПОВНИЙ', екран, екран + вибір, екран + кінець,
            вибір + екран + кінець, палітра + '\nTraceback: обвал',
            '2. збирання (сід 3)\n' + палітра]:
    assert м.сумісний('палітра', лог) is None, лог
for назва, лог, факт in [('палітра', палітра, True), ('палітра +фото', палітра, False),
                         ('палітра +фото', '(FOTO=1)\n' + палітра, True),
                         ('функція', палітра, False), ('функція', 'функція\nготово', None),
                         ('функція', '2. збирання (сід 3)\n2б. чотири картки за 1 с', False)]:
    assert м.сумісний(назва, лог) is факт, (назва, лог)
print('палітра: 1 завершений шлях; 8 непідтверджених; фото; функція без підміни — PASS')
рефи = [('голова1', 'origin/claude/zhyvi-1'), ('голова2', 'origin/claude/zhyvi-2')]
м.рядки = lambda _: []
логи = {'голова1': палітра, 'голова2': екран + вибір}
def г(*а):
    """Дає завершений і обірваний кандидат лише зі сталих SHA refs."""
    if а[0] == 'ls-tree':
        return 'рез/код.txt'
    if а[0] == 'show':
        sha, ф = а[1].split(':', 1)
        return f'код{sha[-1]} сцена ПІСЛЯ модель' if ф.endswith('код.txt') else логи[sha]
    return '10' if а[0] == 'rev-list' else ''
м.г = г
до = м.добрати('сцена', 'кодПІСЛЯ', 'палітра', рефи)
assert до[0][2] == 'код1' and до[1] == (0, 0, 1)
assert м.добрати('сцена', 'кодПІСЛЯ', 'функція', рефи)[0] is None
логи['голова1'] = ''
assert м.добрати('сцена', 'кодПІСЛЯ', 'палітра', рефи)[0] is None
print('добір палітри: завершений кандидат прийнято, обірваний/відсутній відхилено — PASS')
