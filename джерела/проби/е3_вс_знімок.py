"""Ваги знахідок `верхнє_стан` на повному каталозі; аргументи: вихід.json.gz [корінь дерева ДО]."""
import collections, gzip, json, os, pathlib, sys
КОРІНЬ = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else pathlib.Path(__file__).resolve().parents[2])
sys.path.insert(0, str(КОРІНЬ / 'джерела'))


def main():
    """Кожна річ верхнього шару × смуга × вітер × склад образу; кожна річ торса — у парах драбини."""
    import верхнє_стан as В, суд_погода as П, сценарій as С, реєстр_сила as Р
    assert pathlib.Path(В.__file__).resolve().parents[1] == КОРІНЬ.resolve(), В.__file__
    к = json.load(gzip.open(pathlib.Path(os.environ['TMP']) / 'е3_каталог.json.gz', 'rt', encoding='utf-8'))
    перша = lambda умова: next(р for р in к if умова(р))
    обʼємна = перша(lambda р: р.get('тип') in В._ОБʼЄМНІ_ТИПИ and В._товстий_клас(р) and (р.get('оверсайз') or str(р.get('крій')) in В._ВЖЕ_ОБʼЄМНІ_КРОЇ))
    вʼязана = перша(lambda р: р.get('тип') in В._ОБʼЄМНІ_ТИПИ and В._товстий_клас(р) and not р.get('крій') and not р.get('оверсайз'))
    висока = перша(lambda р: р.get('слот') == 'верх' and В._висока_горловина(р))
    шарф, пояс, приталене = (перша(lambda р: р.get('слот') == 'шарф'), перша(lambda р: р.get('слот') == 'пояс'),
                             перша(lambda р: В._структурний(р) and str(р.get('крій')) in В._ПРИТАЛЕНІ_КРОЇ))
    вих, підсумок = [], collections.Counter()
    def запис(назва, функція, зн, смуга=None):
        for з, п in zip(зн, П.придушити([dict(з) for з in зн], П.придушення(смуга))):
            вих.append([назва, функція, з['правило'], з.get('суть'), з.get('сила'), з.get('сила_нп'),
                        Р.обмежити_вагу([dict(з)])[0].get('сила_нп'), Р.обмежити_вагу([п])[0].get('сила_нп')]); підсумок[з['правило']] += 1
    for в in (р for р in к if р.get('слот') == 'верхній_шар'):
        for склад in ([в], [в, обʼємна], [в, вʼязана], [в, висока, шарф]):
            for смуга, н in ((с, '%s+%d@%s' % (в['id'], len(склад), с)) for с in (None,) + С.СМУГИ_ПОГОДИ):
                for вітер in (None, 'strong'):
                    запис(н + '/%s' % вітер, 'стан_знахідки', В.стан_знахідки(склад, смуга, вітер), смуга)
                    for т in (None, 0.3, 3.0):
                        запис(н + '/%s/%s' % (вітер, т), 'команди_укладки', В.команди_укладки(склад, смуга, вітер, т))
                запис(н, 'драбина_припусків', В.драбина_припусків(склад, смуга), смуга)
                for т, г in ((None, None), (None, []), (None, [пояс]), (3.0, None)):
                    запис(н + '/%s/%s' % (т, г and 1), 'ремонти', В.ремонти(склад, смуга, т, г), смуга)
    for р in (р for р in к if р.get('слот') in ('верх', 'сукня', 'комплект', 'верхній_шар')):
        for склад in ([приталене, р], [р, обʼємна], [р, висока]):
            запис('%s|%s' % (склад[0]['id'], склад[1]['id']), 'драбина_шарів', В.драбина_шарів(склад))
    ф = gzip.open(sys.argv[1], 'wt', encoding='utf-8'); json.dump(вих, ф, ensure_ascii=False); ф.close()
    print('знахідок', len(вих), 'правил', dict(sorted(підсумок.items())))

if __name__ == '__main__':
    main()
