# -*- coding: utf-8 -*-
"""K-REG-22 (український етно-реєстр) на живому каталозі. Запуск із теки
`джерела`: `python3 проби/reg_K-REG-22.py`.

Реєстр має вхід у каталозі: 10 речей зі словом «вишиванка» в назві і 99 зі словом
«вишивка». Тема-22 дає когерентну пару «етно × бохо», і саме тому вишиванка
виходить у ДВА реєстри одночасно — це стан, який K-REG-03 називає нормальним
(«річ може належати до кількох реєстрів»), а не конфлікт."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import feed as Ф, реєстри as РЕ

офери, _ = Ф.читати_yml(Ф.каталог_на_диску("каталог_повний.xml"))
етно = [o for o in офери if "етно_укр" in РЕ.реєстр_речі(o)["бали"]]
вишиванки = [o for o in офери if РЕ._є("вишиванк", РЕ._текст(o))]
print("K-REG-22 на живому каталозі: %d речей · зокрема «вишиванка» — %d"
      % (len(етно), len(вишиванки)))
assert вишиванки, "вишиванок у каталозі нема — реєстр лишився б без входу"

зразок = вишиванки[0]
в = РЕ.реєстр_речі(зразок)
print("річ: %s" % (зразок["назва"] or "")[:60])
print("  збіги:", в["збіги"], "· бали:", в["бали"])
assert "етно_укр" in в["бали"], в
print("  впевненість:", РЕ.впевненість("етно_укр")["розпізнавач"])

# пара «етно × бохо» когерентна: штрафу K-REG-05 на ній бути НЕ може (правило
# каже прямо — «бонусу за когерентність система не дає взагалі», і штрафу теж)
print("етно_укр × бохо:", РЕ._пара_статус("етно_укр", "бохо"))
assert РЕ._пара_статус("етно_укр", "бохо") == "когерентна"

# образ із самої вишиванки: реєстр веде, K-REG-01 мовчить — домінанта є
import реєстр_правил as R
зн, о = РЕ.перевірити([зразок], R._зн)
print("образ із однієї вишиванки → домінанта:", о["домінанта"],
      "· знахідки:", [z["правило"] for z in зн])
print("рядок для моделі:", РЕ.словами(о))
