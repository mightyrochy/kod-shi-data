"""Паспорт і розмова у файлі — стан НА МОМЕНТ ЗАПИСУ, а не знімок прогону.

Збирання робить знімок (`ЗБ.паспорт`, `ЗБ.випадок`, `ЗБ.чат`) і коментар у коді
каже «звідси їх бере запис вердикту». Запис бере не звідти: `паспорт`,
`паспорт_джерело` і `випадок_моделі` читають ЖИВІ глобальні `ПАСПОРТ_П` /
`ВИПАДОК_ПАСПОРТА_П`, а `чат` — `ЗБ` ОСТАННЬОГО збирання, не того, з якого картка.
Друк: скільки разів знімок записано й скільки прочитано, і доказ із файла власника.
"""
import json
import pathlib

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
рядки = (КОРІНЬ / "джерела" / "показ.html").read_text(encoding="utf-8").splitlines()
запис = читання = 0
for н, р in enumerate(рядки, 1):
    if "ЗБ.паспорт" in р or "ЗБ.випадок" in р:
        бік = "ЗАПИС " if "ЗБ.паспорт =" in р or "ЗБ.випадок =" in р else "читання"
        запис += бік == "ЗАПИС "
        читання += бік == "читання"
        print("показ.html:%d %s %s" % (н, бік, р.strip()[:100]))
    if "паспорт: JSON.stringify" in р or "випадок_моделі:" in р or "паспорт_джерело:" in р or "чат: JSON.stringify" in р:
        print("показ.html:%d ЗАПИС ВЕРДИКТА бере %s" % (н, р.strip()[:100]))
print("знімок прогону `ЗБ.паспорт`/`ЗБ.випадок`: записів", запис, "· читань", читання,
      "— і жодне читання не в записі вердикта (рядок 8044 — це фото для приміряння)")

ф = КОРІНЬ / "аудит" / "тести" / "власник_2026-09-25" / "verdykty-0phxvk-2026-09-25-2012.json"
д = json.loads(ф.read_text(encoding="utf-8"))
for п in д["прогони"]:
    с = п["спільне"]
    часи = [в.get("час") for в in п["вердикти"]]
    шар = [к.get("коли") for р in (с.get("чат") or []) for к in (р.get("мова_шару") or [])]
    print("розклад", с.get("розклад"), "· вердикти", [т[11:19] for т in часи if т],
          "· мовний шар реплік чату:", [т[11:19] for т in шар if т],
          "· речі з фото в паспорті:", [x.get("ід") for x in (с.get("паспорт") or {}).get("речі_з_фото") or []])
print("чат прогонів 3421 і 4123 однаковий побайтово:",
      json.dumps(д["прогони"][2]["спільне"].get("чат")) == json.dumps(д["прогони"][3]["спільне"].get("чат")))
