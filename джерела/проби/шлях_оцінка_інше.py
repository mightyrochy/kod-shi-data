"""Рядок 830: «Інше» в «Оціни мій образ» — чи губиться нагода, коли жінка пише її словами.
Шлях показу: «Інше» не ставить `нагода` (`сценарійОцінкиП`), її слова з «Що хочеш знати?» йдуть
перекладачеві `scenario` (мовна модель → коди), коди — у `сценарій_слів`, і `оцінка_образу.
сценарій_оцінки` кладе їх у сцену суду поруч із полями екрана. Друкує сцену й суд ошатності для
плитки і для тих самих кодів зі слів. Запуск із `джерела`: python3 проби/шлях_оцінка_інше.py"""
import sys, re; sys.path.insert(0, '.')
import оцінка_образу as О
exec(open('проби/шлях_оцінка_екран_образ.py', encoding='utf-8').read().split('for назва, екран')[0].split('"""', 2)[2])
T = open('показ.html', encoding='utf-8').read()
ряд = lambda взір: T[:re.search(взір, T).start()].count('\n') + 1
print("показ: «Інше» нагоди не ставить (показ.html:%d); слова → перекладач scenario (показ.html:%d);"
      " коди → `сценарій_слів` (показ.html:%d)" % (
      ряд(r"if \(н && н !== ІНШЕ_ОЦІНКИ_П\) с\.нагода = н"),
      ряд(r"перекластиП\('scenario', слова, null, 'review'\)"),
      ряд(r"сценарійСлів \? \{сценарій_слів: сценарійСлів\}")))
def сцена(екран, слова, ош=None):
    рр = [dict(р, ошатність=ош) for р in речі] if ош else речі
    с = О.суд(dict(вх, речі=рр, сценарій_оцінки=екран, сценарій_слів=слова, крамниця=False))
    ош = sorted({з["правило"] for з in с["суд"]["findings"] if str(з["правило"]).startswith(("K-KOH", "K-OCC"))})
    return с["сцена"].get("нагода"), с["сцена_звідки"].get("нагода"), ош, [б["input"] for б in с["без_входу"] if б.get("input")]
for назва, *х in (("нічого не назвала", {}, None),
                            ("плитка «Робота»", {"нагода": "робота"}, None),
                            ("«Інше» + «на роботу» → occasion=work", {}, {"occasion": "work"}),
                            ("«Інше» + «на похорон» → occasion=mourning", {}, {"occasion": "mourning"}),
                            ("«Інше» + «гостею на весілля» → wedding_guest", {}, {"occasion": "wedding_guest"}),
                            ("те саме, речі ошатністю 2, без числа моделі", {}, {"occasion": "wedding_guest"}, 2),
                            ("те саме, речі ошатністю 2, formality 7–9", {}, {"occasion": "wedding_guest",
                                                                             "formality": {"from": 7, "to": 9}}, 2)):
    н, звідки, ош, бв = сцена(*х)
    print("  %-46s нагода суду: %-13s звідки: %-9s ошатність: %-12s без входу: %s" % (
          назва, н or "—", звідки or "—", "+".join(ош) or "—", ", ".join(бв) or "—"))
assert сцена({"нагода": "робота"}, None)[0] == сцена({}, {"occasion": "work"})[0] == "робота", "нагода зі слів ≠ плитці"
assert сцена({}, {"occasion": "mourning"})[2], "нагода зі слів не судиться"
assert "occasion" not in сцена({}, {"occasion": "work"})[3], "нагода зі слів досі «без входу»"
assert сцена({}, {"occasion": "wedding_guest", "formality": {"from": 7, "to": 9}}, 2)[2], "смуга зі слів не судиться"
print("→ нагода зі слів після «Інше» не губиться: мовна модель дає код, суд стоїть на ньому, як на плитці;"
      "\n  смуга ошатності (після НП-в — лише число мовної моделі) зі слів тепер теж іде в сцену."
      "\n  Без мовного шару (MODEL_MOVA=нема) слів ніхто не тлумачить — код їх не читає (п.12).")
