# -*- coding: utf-8 -*-
"""Рядки 1860, 2041: K-COL-03 'нейтрали+акцент' бачить хроматичну вставку срібної прикраси.
Срібло з синьою вставкою + червона сумка → два тони (знахідка); вставка + нейтраль → один акцент (мовчить)."""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import palettes as ПЛ, colorspace as cs
спец = {"_схема": "нейтрали+акцент", "верх": {"роль": "база", "C": [0, 8]},
        "сережки": {"роль": "акцент", "C": [30, 70]}, "сумка": {"роль": "акцент", "C": [30, 70]}}
lab = lambda hx: list(cs.hx(hx))
верх = dict(id="v", слот="верх", hex="#d8d4cc", назва="v")
сер = dict(id="s", слот="сережки", hex="#c0c0c0", метал="срібло", назва="s",
           колір_вставки=[dict(lab=lab("#1f4fd8"), частка=0.3)])
сумка = dict(id="b", слот="сумка", hex="#c8102e", назва="b")
нейтр = dict(id="n", слот="сумка", hex="#8a8a8a", назва="n")
def з(речі):
    return [x["ярлик"] for x in ПЛ.обіцянка_схеми(речі, спец, {r["id"]: r for r in речі}) if x["правило"] == "K-COL-03"]
print("срібло+синя вставка + червона сумка (очікую знахідку):", з([верх, сер, сумка]) or "—")
print("срібло+синя вставка + сіра сумка (один акцент, очікую —):", з([верх, сер, нейтр]) or "—")
