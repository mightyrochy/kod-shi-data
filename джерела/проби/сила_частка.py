"""Нормований вплив і придушення ваги: нуль, стелі та незмінність входу."""
import pathlib
import sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import реєстр_сила as С


def main():
    """Перевірити частку виміру та частку готової ваги на межах шкали."""
    for сила, стеля in С.КАТ_У_НП.items():
        for частка in (0, 0.01, 0.25, 0.5, 1):
            assert С.неперервна_сила(сила, частка=частка)[0] == min(частка, стеля)
    assert С.неперервна_сила('soft', вимір=0, поріг=0, повна=1)[0] == С.підлога_нп()
    for сила in С.БЕЗ_ВЕРДИКТУ:
        assert С.неперервна_сила(сила, частка=1)[0] == 0
    з = С.зн('K-WEA-05', 'strong', 'замша у дощ', [], 'умова', частка=1)
    assert з['сила_нп'] == С.КАТ_У_НП[з['сила']]
    for частка in (0, 0.25, 1):
        нова = С.перезважити(з, None, частка=частка)
        assert нова['сила_нп'] == round(з['сила_нп'] * частка, 2)
        assert нова['сила'] == з['сила'] and нова['регістр'] == з['регістр']
        assert частка != 0 or not нова['блокує']
    assert з['сила_нп'] == С.КАТ_У_НП[з['сила']]
    без = dict(з)
    без.pop('сила_нп')
    assert 'сила_нп' not in С.перезважити(без, None, частка=0)
    for частка in (-0.1, 1.1, float('nan')):
        for виклик in (lambda: С.неперервна_сила('soft', частка=частка),
                        lambda: С.перезважити(з, None, частка=частка)):
            try:
                виклик()
            except ValueError:
                continue
            raise AssertionError(частка)
    print('частки: нуль і підлога різні; стелі, стани, придушення й копія — справні')


if __name__ == '__main__':
    main()
