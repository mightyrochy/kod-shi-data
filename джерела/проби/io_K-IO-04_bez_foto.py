# -*- coding: utf-8 -*-
"""K-IO-04 · промпт вибору (виклик 3) з фото і без — рядок 105 дошки:
`python3 проби/io_K-IO-04_bez_foto.py`.

Друкує факт: які рядки промпта є ЛИШЕ з фото, які ЛИШЕ без фото, скільки спільних;
і що розбір (`ід_з_тексту`, `речі_з_тексту`) читає відповідь обох форм — з
«ЧАСТИНА 1/2» і без. Свідок режиму один: константи `brief`
(`_рядки_режиму_фото`), тож рядки нижче — ті самі, що бачать руки."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import повнота_образу as П, розбір_відповідей as Р, brief as Б

образи = [dict(підпис="о1", речі=[], свідомі=["пояс поверх жакета"], блокує=[],
               знахідки=[dict(суть="контраст біля обличчя нижчий за власний")]),
          dict(підпис="о2", речі=[], свідомі=[], блокує=["нема сумки"], знахідки=[])]
без = П.промпт_вибору(образи, "офіс", без_фото=True).splitlines()
з = П.промпт_вибору(образи, "офіс", без_фото=False).splitlines()
лише_з, лише_без = [l for l in з if l not in без], [l for l in без if l not in з]
print("рядків: без фото %d · з фото %d · спільних %d" % (len(без), len(з), len(set(без) & set(з))))
print("ЛИШЕ З ФОТО (%d):" % len(лише_з)); [print("   +", l[:96]) for l in лише_з]
print("ЛИШЕ БЕЗ ФОТО (%d):" % len(лише_без)); [print("   −", l[:96]) for l in лише_без]
свідок = set(Б.ЗАВДАННЯ.splitlines() + Б.ФОРМАТ.splitlines() + Б.ЗАВДАННЯ_БЕЗ_ФОТО.splitlines()
             + Б.ФОРМАТ_ЛИШЕ_ТЕКСТ.splitlines())
print("усі режимні рядки — з констант brief:", all(l in свідок for l in лише_з + лише_без))
опис = ("1. Сукня-футляр міді, графітова, вовна.\n2. Човники чорні, сумка структурна.\n"
        "3. Одна вертикаль світлоти тримає лінію.\nОБРАЗ: ж-1@a.ua, ж-2@b.ua")
текст_без = "ВІДПОВІДЬ — ТІЛЬКИ ТЕКСТ:\n" + опис
текст_з = "ЧАСТИНА 1 — ТІЛЬКИ ТЕКСТ, без зображення:\n" + опис + "\nЧАСТИНА 2 — [зображення]"
канд = dict(низ=[dict(id="ж-1@a.ua", назва="Сукня")], взуття=[dict(id="ж-2@b.ua", назва="Човники")])
ід = {}
for назва, т in (("без фото", текст_без), ("з фото", текст_з)):
    ід[назва] = Р.ід_з_тексту(т, кандидати=канд)
    print("розбір %-8s → ід %s · %s · речей з тексту %d"
          % (назва, ід[назва]["ід"], ід[назва]["джерело"], len(Р.речі_з_тексту(т))))
assert ід["без фото"]["ід"] == ід["з фото"]["ід"] == ["ж-1@a.ua", "ж-2@b.ua"]
assert any("фото людини" in l for l in лише_з) and not any("фото" in l for l in без)
assert any("ТІЛЬКИ ТЕКСТ, без зображення" in l for l in без)
