/* Е2-межі п.3 класу — запасний хід вхідного перекладача (`перекластиП`, показ/мовний_шар.js).
   Три види входу × три збої після повтору (міст кидає, модель кидає, відповідь двічі не пройшла перевірку) і
   один успіх. Втрата — збій, після якого показ не має сталого напису для неї (`запасна` → `ШАБЛОНИ_ЗБОЮ_П`, текст
   проходить сторожа мови); хибна — запасна на успіху. Запуск (з кореня): node джерела/проби/е2_збій_перекладу.js;
   ДО — E2_SOURCES=<тека джерел бази>. Код 1 — є втрати чи хибні. */
const fs = require('fs'), path = require('path'), vm = require('vm');
const src = process.env.E2_SOURCES || path.resolve(__dirname, '..');
const c = vm.createContext({console, Date, МОДЕЛЬ_МОВИ_П: 'запис', ПАСПОРТ_П: null, ЧАТ_П: []});
vm.runInContext(fs.readFileSync(path.join(src, 'показ/мовний_шар.js'), 'utf8'), c);
const шаблони = vm.runInContext('typeof ШАБЛОНИ_ЗБОЮ_П === "object" ? ШАБЛОНИ_ЗБОЮ_П : {}', c);
const ЗБОЇ = {
  'міст кидає': {міст: async () => { throw Error('bridge_down'); }},
  'модель кидає': {міст: async () => ({промпт: 'П'}), модель: async () => { throw Error('model_unavailable'); }},
  'двічі не прийнято': {міст: async (_, д) => д.відповідь_моделі == null ? {промпт: 'П'}
                                                  : {причина: 'not_json', внутрішня: {}}},
  'успіх': {міст: async (_, д) => д.відповідь_моделі == null ? {промпт: 'П'} : {внутрішня: {reasons: ['fit']}}},
};
(async () => {
  const л = {випадків: 0, втрат: 0, хибних: 0}, приклади = [];
  for (const вид of ['review_items_fix', 'verdict_comment', 'question'])
    for (const [збій, м] of Object.entries(ЗБОЇ)){
      c.містП = м.міст; c.модельМовиП = м.модель || (async () => '{}');
      const р = await c.перекластиП(вид, 'сукня не мого кольору', null, 'проба');
      const текст = р.запасна ? шаблони[р.запасна] : '';
      const добрий = !!текст && (typeof c.станТекстуЖінціП !== 'function' || c.станТекстуЖінціП(текст) === 'translated');
      л.випадків++;
      if (збій === 'успіх'){ if (р.запасна) л.хибних++; continue; }
      if (!добрий){ л.втрат++; приклади.push([вид, збій, р.запис.причина]); }
      else if (приклади.length < 6) приклади.push([вид, збій, р.запасна, текст]);
    }
  приклади.forEach(п => console.log(JSON.stringify(п)));
  console.log('втрат після повтору:', л.втрат, 'з', л.випадків - 3, '· хибних запасних:', л.хибних);
  process.exitCode = л.втрат || л.хибних ? 1 : 0;
})();
