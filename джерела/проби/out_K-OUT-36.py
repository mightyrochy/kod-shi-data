# -*- coding: utf-8 -*-
"""K-OUT-36 (драбина припусків діє ЛИШЕ в застібнутому стані).

ДО ПРАВКИ: знахідка народжувалась із `сила_нп=0.0` — «вимикач, не штраф». З
16.09 нульова вага гине у вердикті (`знахідки_вердикту` → `_питання_або_нуль`),
тож вимикач спрацьовував МОВЧКИ: `return` знімав K-OUT-06, K-OUT-30 і K-OUT-08,
і жоден рядок не казав чому.
ПІСЛЯ: вага — корпусна `default` (0.5), і рядок стоїть у вердикті поруч із
відсутністю трьох правил драбини.

ЗБІЛЬШЕННЯ КАТАЛОГУ (PR #81, 18.09.2026, 10 770→12 426 речей): «однобортне»
бралось лише серед кандидатів СТЕНД-ПУЛУ слота «верхній_шар» (`з["кандидати"]`
— K речей, обраних семплером). Пул на зрослому каталозі жодного разу не впіймав
однобортну річ чи річ «без застібки» — `взяти` мовчки віддавав `None`, і
`dict(None, слот=…)` падав `TypeError` двома рядками нижче, а не на вході. Пул —
випадкова вибірка з каталогу, а не саме джерело; проба тепер шукає вхід у
ВСЬОМУ каталозі (`bridge.каталог_останнього_пакета` — те саме джерело, з якого
пул лише семплується) і падає названим полем і числом, якщо такої речі нема
ніде, а не мовчазним `None`."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, outer as OU

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
вх["сценарій"].update(темп_c=12, опади="ні")
B.виклик("запити", json.dumps(вх, ensure_ascii=False))  # будує й кешує пакет — звідти каталог_останнього_пакета()
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
# ВХІД ШУКАЄМО В КАТАЛОЗІ, НЕ В ПУЛІ: пул — K речей на слот, обраних
# семплером, і його склад не обіцяє жодної конкретної властивості. Каталог —
# те саме джерело, з якого пул лише семплюється; перша річ слота з потрібною
# ознакою — вхід, на якому правило взагалі МОЖЕ показатись.
взяти = lambda сл, ум: next((c for c in кат.values()
                             if c.get("слот") == сл and ум(c)), None)
_верх_каталог = [c for c in кат.values() if c.get("слот") == "верхній_шар"]
# дефолт «розстібнуто» дає однобортність (K-OUT-09) або оголошене «без застібки»
однобортне = взяти("верхній_шар", lambda c: c.get("бортність") == "однобортне"
                   or c.get("застібка") == "нема")
assert однобортне is not None, (
    "серед %d речей каталогу зі слотом «верхній_шар» жодна не несе "
    "бортність=однобортне чи застібка=нема — вхід K-OUT-36 недосяжний"
    % len(_верх_каталог))
ід = [r["id"] for r in (однобортне, взяти("сукня", lambda c: True),
                        взяти("взуття", lambda c: True)) if r]
ст = OU.стан([dict(однобортне, слот="верхній_шар")], темп_c=12)
print("верхній шар:", однобортне["назва"][:50], "· бортність", однобортне.get("бортність"),
      "· застібка", однобортне.get("застібка"))
print("однобортних/без застібки в каталозі зі слотом «верхній_шар»: %d з %d" % (
      sum(1 for c in _верх_каталог
          if c.get("бортність") == "однобортне" or c.get("застібка") == "нема"),
      len(_верх_каталог)))
print("дефолт стану:", ст.get("дефолт"))
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
зн = ((вм.get("вердикт") or {}).get("образи") or [{}])[0].get("знахідки") or []
р = next((z for z in зн if z.get("правило") == "K-OUT-36"), None)
print("K-OUT-36 у вердикті:", "НЕМА" if not р else
      "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:60]))
print("правила драбини, яких вимикач зняв:",
      [к_ for к_ in ("K-OUT-06", "K-OUT-30", "K-OUT-08")
       if not any(z.get("правило") == к_ for z in зн)])
