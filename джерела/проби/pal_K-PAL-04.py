# -*- coding: utf-8 -*-
"""K-PAL-04 (аналогова) — умова прийому судить образ.

Корпус (тема-2:1850): «сусідні сім'ї палітри з кроком світлоти між ними;
низький/середній контраст; на високому крок ΔL обовʼязковий». Умова рахувалась у
`palettes.прийоми` і вирішувала лише, чи називати прийом ДОСТУПНИМ. Що образ
реалізує саме аналогову пару — не питав ніхто.
ПІСЛЯ: `pipeline.палітра_образу` спершу ВПІЗНАЄ прийом (одна сім'я / сусідні /
комплемент / нейтралі+акцент) і лише тоді перевіряє умову впізнаного — не всіх
підряд, інакше на кожен образ висипалось би по чотири hint-и. Крок світлоти
всередині пари перевіряє `набір_законний` (K-PAL-15), тож тут лишається сама
придатність прийому цій людині.
Запуск із теки `джерела`: `python3 проби/pal_K-PAL-04.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import palettes as PAL, pipeline as PL

вх, r, кат, спец = ПВ.стенд(гілка=0, самозвіт={"метал": "золото"})
П = спец["палітра_практична"]
акт = {x["прийом"] for x in П["прийоми"] if x["активний"]}
пор = list(PAL.СІМ_Ї)
сім = lambda h: next((ім for ім, в in PAL.СІМ_Ї.items()
                      for a in (в.get("тепла"), в.get("холодна")) if a
                      and ((a[0] <= h <= a[1]) if a[0] <= a[1] else (h >= a[0] or h <= a[1]))), None)
кольоровий = lambda L, C, h, _: not PL._нейтральний_тон(h, C, L)
верх = ПВ.взяти(r, кат, "верх", кольоровий) or ПВ.взяти(r, кат, "сукня", кольоровий)
s1 = сім(ПВ.lch(кат, верх["id"])[2]) if верх else None
сусід = lambda L, C, h, _: (кольоровий(L, C, h, _) and сім(h) and s1
                            and abs(пор.index(сім(h)) - пор.index(s1)) == 1)
низ = next((x for с in ("низ", "шарф", "прикраси", "головний_убір", "сумка")
            for x in [ПВ.взяти(r, кат, с, сусід)] if x), None)
решта = [ПВ.взяти(r, кат, с, lambda *a: True) for с in ("взуття", "сумка")]
print("прийом «аналогова» доступний цій людині: %s · пара сімей: %s + %s"
      % ("аналогова" in акт, s1, сім(ПВ.lch(кат, низ["id"])[2]) if низ else "—"))
if низ:
    ід = [x["id"] for x in [верх, низ] + решта if x]
    зн, _ = ПВ.знахідки(вх, ід)
    print("ФАКТ · K-PAL-15 над цією парою (крок світлоти між сім'ями — те, що K-PAL-04 "
          "вимагає): %s" % ПВ.рядок(зн, "K-PAL-15"))
else:
    print("      кольорової речі сусідньої сім'ї в пулі нема — пару скласти нема з чого; "
          "два канали нижче від пулу не залежать")
# K-PAL-04 НЕ МАЄ ВЛАСНОЇ ЗНАХІДКИ, І ЦЕ СКАЗАНО ВГОЛОС: корпус не вимикає аналогову
# на жодному контрасті, а те, що вона стверджує над образом (крок ΔL між сім'ями),
# уже міряє `набір_законний` тим самим `step_min` K-COL-01. Правило діє двома іншими
# каналами, і обидва тут видно.
трійки = [p for p in (П.get("поєднання") or []) if p["прийом"] == "аналогова"]
пакет = [x for x in (PAL.для_пакета(П).get("прийоми") or []) if x["прийом"] == "аналогова"]
print("ФАКТ · K-PAL-04 діє: породив %d аналогових трійок палітри (%s) і стоїть у пакеті "
      "й описі серед доступних прийомів: %s"
      % (len(трійки), "; ".join(" + ".join(c["назва"] for c in t["кольори"]) for t in трійки[:2]),
         bool(пакет)))
assert пакет, "прийом не доїжджає до моделі"
