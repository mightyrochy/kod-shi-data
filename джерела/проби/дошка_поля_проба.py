# -*- coding: utf-8 -*-
"""Контракт PR, сумісне згортання й тиждень із самої дошки в пісочниці."""
import re, sys, tempfile
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'прилади'))
import згорнути_дошку as згортання
from дошка_зріз import читати_дошку, підрахувати
from дошка_поля import ПЕРШИЙ_СУВОРИЙ_НОМЕР, метадані, перевірити_поля
from дошка_дати_сценарії import перевірити_хронологію
без = lambda т, п: '<!-- дошка: ' + '; '.join(f'{к}={з}' for к, з in метадані(т).items() if к != п) + ' -->'
Р = lambda н, стан='**ВІДКРИТО**', поля='': f'| {н} | проба | низька | {стан} | опис | файл | виявлено: проба; внесено: давнє {поля} |'
нове = '<!-- дошка: дата=2026-10-26; рід=видима; попередник=тема 1; механізм=копія-поняття -->'
кінець = '<!-- дошка: механізм=копія-поняття; закриття=корінь; доказ=нема; дата-закриття=2026-10-26 -->'
with tempfile.TemporaryDirectory() as тека:
    корінь = Path(тека); (корінь / 'фрагменти').mkdir()
    згортання.КОРІНЬ, згортання.ДОШКА, згортання.ТЕКА = тека, str(корінь / 'дошка.md'), str(корінь / 'фрагменти')
    дошка = Path(згортання.ДОШКА); фрагмент = Path(згортання.ТЕКА) / 'проба.md'; Н = 10176
    перевірити_хронологію(дошка, фрагмент, Р, нове, кінець)
    дошка.write_text(Р(1) + '\n' + Р(Н + 1) + '\n', encoding='utf-8')
    for поле in ('дата', 'рід', 'попередник', 'механізм'):
        фрагмент.write_text(Р(Н, поля=без(нове, поле)), encoding='utf-8')
        assert any(f'поле {поле}:' in п for п in згортання.згорнути(True)[1]), поле
    for поле in ('механізм', 'закриття', 'доказ', 'дата-закриття'):
        фрагмент.write_text(f'стан {Н + 1}: **ЧАСТКОВО** ' + без(кінець, поле), encoding='utf-8')
        assert any(f'поле {поле}:' in п for п in згортання.згорнути(True)[1]), поле
    for попередник in ('тема 99', f'тема {Н}', 'повернення закритого 1'):
        фрагмент.write_text(Р(Н, поля=нове.replace('тема 1', попередник)), encoding='utf-8')
        assert any('поле попередник:' in п for п in згортання.згорнути(True)[1]), попередник
    фрагмент.write_text(Р(Н, поля=нове) + f'\nстан {Н + 1}: **ЗАКРИТО** ' + кінець, encoding='utf-8')
    до = дошка.read_bytes(); assert not згортання.згорнути(True)[1] and дошка.read_bytes() == до
    assert not згортання.згорнути()[1] and not фрагмент.exists()
    Н7 = Н + 7
    # Д7: ЗАКРИТО продукту з доказом «проба» — червоне; ЧАСТКОВО, доказ=живий і не-продукт — зелені.
    проба_закриття = кінець.replace('доказ=нема', 'доказ=проба')
    for рід, стан, чекаємо in (('видима', 'ЗАКРИТО', True), ('внутрішня', 'ЗАКРИТО', True), ('дані', 'ЗАКРИТО', True),
                               ('видима', 'ЧАСТКОВО', False), ('процес', 'ЗАКРИТО', False), ('мірило', 'ЗАКРИТО', False)):
        нове_р = нове.replace('рід=видима', f'рід={рід}')
        фрагмент.write_text(Р(Н7, поля=нове_р) + f'\nстан {Н7}: **{стан}** ' + проба_закриття, encoding='utf-8')
        assert any('з доказом «проба»' in п for п in згортання.згорнути(True)[1]) == чекаємо, (рід, стан)
        фрагмент.write_text(f'стан {Н + 1}: **{стан}** ' + проба_закриття, encoding='utf-8')
        assert not any('з доказом «проба»' in п for п in згортання.згорнути(True)[1]), 'стан без роду'
    фрагмент.write_text(Р(Н7, поля=нове) + f'\nстан {Н7}: **ЗАКРИТО** ' + кінець.replace('доказ=нема', 'доказ=живий'), encoding='utf-8')
    assert not згортання.згорнути(True)[1], 'живий'
    фрагмент.unlink()
    # Наявна дошка: жодного ЗАКРИТО продукту з доказом «проба», крім рядків, що цей PR переводить на ЧАСТКОВО.
    корінь_репо = Path(__file__).resolve().parents[2]
    ще_не_згорнуто = {m for ф in (корінь_репо / 'аудит' / 'дошка').rglob('*.md')
                      for m in re.findall(r'^стан!? (\d+): \*\*ЧАСТКОВО', ф.read_text(encoding='utf-8'), re.M)}
    for р in (корінь_репо / 'аудит' / 'БЕКЛОГ.md').read_text(encoding='utf-8').split('\n'):
        м = згортання.РЯДОК.match(р)
        if not м or int(м[1]) < ПЕРШИЙ_СУВОРИЙ_НОМЕР or м[1] in ще_не_згорнуто or not згортання.межі_стану(р):
            continue
        від, до = згортання.межі_стану(р)
        вади = перевірити_поля(р[від:до], закрито=True, рід=метадані(р[:від] + р[до:]).get('рід', ''),
                               повне=згортання.ранг_рядка(р) > 2)
        assert not [в for в in вади if 'з доказом «проба»' in в], (м[1], вади)
    записи, старі = читати_дошку(дошка); числа = підрахувати(записи, '2026-10-26', '2026-11-01')
    assert (числа['нових'], числа['повтор'], числа['закриттів'], числа['без доказу'], числа['видимих авто']) == (1, 1, 1, 1, 1)
    фрагмент.write_text(f'стан {Н}: **ЗАКРИТО** ' + кінець, encoding='utf-8')
    assert not згортання.згорнути(True)[1] and not згортання.згорнути()[1]
    assert next(р for р in читати_дошку(дошка)[0] if р['номер'] == str(Н))['дата'] == '2026-10-26'
    for текст in (Р(Н - 1), 'стан 1: **ЧАСТКОВО**', 'заміна ' + Р(1, '**ЗАКРИТО**')):
        фрагмент.write_text(текст, encoding='utf-8'); assert not згортання.згорнути(True)[1], текст
    фрагмент.write_text(Р(Н + 2), encoding='utf-8'); assert згортання.згорнути(True)[1] and not згортання.згорнути()[1]
print('PR: ≤10175 без полів і старі закриття прийнято; ≥10176 без полів відхилено; нові 8 полів обов’язкові; тиждень 1/1, видимих авто 1/1; дата пережила закриття')
