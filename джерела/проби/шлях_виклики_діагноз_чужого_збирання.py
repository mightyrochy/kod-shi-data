"""Розбір шляху 4/8 · «збій — HTTP 413» у записі руки, яка не впала. Файл власника 2012, прогін 4123, рука 1: чи
дійшла рука до кінця (виклики, опис, приміряння) — і що каже її `етапи.діагноз_руки`. Рядок «рука N: збій — …»
пише лише catch усієї руки (`показ.html`), і той самий catch скидає `в` → картка без опису. `етапиЗапису` бере
діагноз із ПОТОЧНОГО збирання в мить вердикта. Друкує факти файлу й ці рядки коду.
Запуск: cd джерела && python3 проби/шлях_виклики_діагноз_чужого_збирання.py"""
import json, os, re
тут = os.path.dirname(os.path.abspath(__file__))
д = json.load(open(os.path.join(тут, "../../аудит/тести/власник_2026-09-25/verdykty-0phxvk-2026-09-25-2012.json"), encoding="utf-8"))
п = д["прогони"][3]; в = п["вердикти"][0]; е = в["етапи"]
print("прогін: %s · рука %s" % (п["прогін"], в["рука"]))
for x in е["виклики"]:
    print("  %-20s запит %6d симв., фото %s · відповідь %5d симв. · перевірено %s"
          % (x["крок"], len(x["запит"]["текст"]), x["запит"].get("фото"), len(x.get("відповідь_сира") or ""), x.get("перевірено")))
print("  опис на картці %d симв. · як_носити %d · приміряння: %s, картинка %s · вердикт жінки «%s»"
      % (len(в.get("опис") or ""), len(в.get("як_носити") or []), в.get("примірка_режим"), bool(в.get("примірка_картинка")), в.get("вердикт_людини")))
print("  діагноз_руки: %s" % е.get("діагноз_руки"))
к = open(os.path.join(тут, "../показ.html"), encoding="utf-8").read().split("\n")
for і, р in enumerate(к):
    if "': збій — '" in р or re.search(r"function етапиЗапису|const д = \(\(ЗБ && ЗБ\.діагноз\)", р) or "текст = ''; в = {перевірено:false}" in р:
        print("  показ.html:%d  %s" % (і + 1, р.strip()[:110]))
стеля = open(os.path.join(тут, "../worker.js"), encoding="utf-8").read()
print("  worker.js: %s" % re.search(r"const розмір = [^;]+;", стеля).group(0))
