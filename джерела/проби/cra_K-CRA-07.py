"""K-CRA-07 (мікс металів без повтору) на живому шляху: `python3 проби/cra_K-CRA-07.py`.

ЧОМУ СЛІДУ НЕ БУЛО: `суд_образу.метали` починається з `[e for e in E if e.get("метал")]`,
а поле `метал` до суду не доїжджало. Запис каталогу `параметри` не несе, тож
`composer._у_річ` вгадував метал із голої НАЗВИ й лише в ювелірних слотах: 9 речей
із 10 770, усі «золото» — один тон, тобто міксу не могло бути за побудовою.
Після правки метал читається з ПОЛЯ картки (`параметри["метал"]`) словником самого
суду: 60 речей — золото 28, сталь 15, срібло 15, латунь 2."""
import sys, pathlib, json
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B

вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["гілка"] = 0
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
з_металом = [c for c in кат.values() if c.get("метал")]
тони = sorted({c["метал"] for c in з_металом})
print("каталог пакета: речей із металом %d, тонів %d — %s"
      % (len(з_металом), len(тони), ", ".join(тони)))
assert len(тони) >= 2, "одного тону досить для мовчання правила — міксу нема"

# річ береться з КАТАЛОГУ пакета, а не лише з пулу: `перевірити_від_моделі` законно
# судить річ поза кандидатами (вона лягає в `поза_кандидатами`) — тим самим шляхом,
# яким у продукт заходить річ, знайдена моделлю в повному каталозі.
один = next(c for c in з_металом if c["метал"] == "сталь")
двоє = [c for c in з_металом if c["метал"] == "золото"][:2]
база = [next(c for c in кат.values() if c["слот"] == сл) for сл in ("сукня", "взуття")]
ід = [c["id"] for c in база + двоє + [один]]
print("образ:", [(кат[i]["слот"], кат[i].get("метал")) for i in ід])
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
з = next((z for z in (о.get("знахідки") or []) if z["правило"] == "K-CRA-07"), None)
print("K-CRA-07 у вердикті:", "НЕМА" if not з else
      "%s %.2f · %s" % (з["сила"], з["сила_нп"], з["суть"][:60]))
print("речі рядка:", (з or {}).get("речі"), "· регістр", (з or {}).get("регістр"))
assert з, о.get("знахідки")
