"""КОЛІР-ФІД-3 (рядок 3122): речі з полем кольору, яке `V.слово_крамниці` читає, а `V.вікно_зі_слова` — ні
(іншомовне «Blue», «Burgundy», «Powder»; «денім», «Пломбір», «фуксія»), на `каталог_повний` (рука 1).
Друкує: скільки таких оферів, скільки з них у каталозі (і чим колір: точка/вікно), скільки випало, приклади.
Запуск із джерела/: python3 проби/колір_іншомовне_поле_3122.py"""
import sys, collections as K
sys.path.insert(0, "."); import feed as F, фід_каталог as ФК, verify as V, колір_річ as КР
from фід_розбір import читати_yml, _СЕП_КОЛЬОРУ
F.каталог_на_диску("каталог_повний.xml")
р = ФК._прочитати_каталог("каталог_повний.xml", 0)
кат = {r["id"]: r for r in р["каталог"]}
офери = читати_yml("каталог_повний.xml")[0]
def читає(o):
    поле = o.get("колір_сирий") or o.get("колір_назва") or ""
    return next(filter(None, map(V.слово_крамниці, _СЕП_КОЛЬОРУ.split(поле))), None)
цілі = [o for o in офери if not V.вікно_зі_слова(str(o.get("колір_назва") or o.get("назва") or "").lower())[0] and читає(o)]
вид = lambda r: "вікно" if КР.не_вимір(r) else "точка"
у = [o for o in цілі if o["id"] in кат]; поза = [o for o in цілі if o["id"] not in кат]
print("каталог речей:", len(кат), "· офери з полем, яке читає лише слово_крамниці:", len(цілі))
print("у каталозі:", len(у), dict(K.Counter(вид(кат[o["id"]]) for o in у)), "· випали:", len(поза))
print("випали за крамницею:", dict(K.Counter(o.get("магазин") or o["id"].split("@")[-1] for o in поза).most_common()))
for o in поза[:12]:
    ск = читає(o); print("  %-28s «%s» → %s" % (o["id"], o.get("колір_сирий") or o.get("колір_назва"), ск["ім"]))
