"""Проба Н-02-03 (С-62): чотири ендпойнти без викликача знесено, ті, що мають
читача, — на місці. Друкує факти. Прогін: python3 проби/с62_мертві_ендпойнти.py"""
import json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import bridge as B, pipeline as PL

ЗНЕСЕНІ = ("тони", "кольори", "пояснення", "приміряння")
ЛИШЕНІ = ("палітри", "запити", "від_моделі", "опис", "показ", "паспорт",
          "вердикт", "довідник", "чипи", "порада")
СИРОТИ_МОСТА = ("_згода_зчитувань_шкіри", "_hex_lab", "_слово", "_МЕЖІ_L",
                "_СЛОВА", "АХРОМАТИЧНА_МЕЖА")
СИРОТИ_КОНВЕЄРА = ("пакет_пояснення", "пояснення_від_моделі", "запит_приміряння")

def диспетчер_знає(ім):
    """KeyError САМЕ З ІМЕНЕМ ЕНДПОЙНТА = диспетчер його не знає. Будь-яка інша
    помилка (зокрема KeyError зсередини на порожньому вході — так падають
    `запити`, `опис`, `показ`) означає, що виклик УЖЕ пішов у функцію."""
    try:
        B.виклик(ім, "{}")
    except KeyError as e:
        return e.args[:1] != (ім,)
    except Exception:
        return True
    return True

print("знесені ендпойнти (має бути «нема» в обох колонках):")
for ім in ЗНЕСЕНІ:
    print("  %-12s функція: %-5s диспетчер: %s"
          % (ім, "є" if hasattr(B, ім) else "нема",
             "знає" if диспетчер_знає(ім) else "нема"))
print("ендпойнти з читачем (має бути «є» в обох):")
for ім in ЛИШЕНІ:
    print("  %-12s функція: %-5s диспетчер: %s"
          % (ім, "є" if hasattr(B, ім) else "нема",
             "знає" if диспетчер_знає(ім) else "нема"))
print("сироти, що трималися лише знесеними ендпойнтами:")
for ім in СИРОТИ_МОСТА:
    print("  bridge.%-24s %s" % (ім, "ЩЕ Є" if hasattr(B, ім) else "нема"))
for ім in СИРОТИ_КОНВЕЄРА:
    print("  pipeline.%-22s %s" % (ім, "ЩЕ Є" if hasattr(PL, ім) else "нема"))
print("живий виклик того, що лишилось: чипи віддають %d шкал"
      % len(json.loads(B.виклик("чипи", "{}"))))
