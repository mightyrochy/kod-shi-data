# -*- coding: utf-8 -*-
"""Свідома правка дати появи та стан після заміни проходять спільну перевірку хронології."""
import sys, tempfile
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'прилади'))
import згорнути_дошку as згортання


if __name__ == '__main__':
    рядок = lambda д: ('| 6977 | факт <!-- дошка: дата=' + д + '; рід=процес; попередник=ні; механізм=інше --> '
                       '| низька | **ВІДКРИТО** | виявлено: диспетчер; внесено: давнє |')
    кінець = '**ЧАСТКОВО** <!-- дошка: механізм=інше; закриття=корінь; доказ=проба; дата-закриття=2026-10-30 -->'
    with tempfile.TemporaryDirectory() as тека:
        т = Path(тека); (т / 'фрагменти').mkdir()
        згортання.КОРІНЬ, згортання.ДОШКА, згортання.ТЕКА = тека, str(т / 'дошка.md'), str(т / 'фрагменти')
        згортання.КОРЕНІ = str(т / 'корені')
        дошка, фрагмент = Path(згортання.ДОШКА), т / 'фрагменти' / 'проба.md'
        дошка.write_text(рядок('2026-10-26'), encoding='utf-8')
        for дата in ('2026-10-17', '2026-11-04'):
            for свідомо in ('', '!'):
                for стан in ('', '\nстан 6977: ' + кінець):
                    фрагмент.write_text('заміна' + свідомо + ' ' + рядок(дата) + стан, encoding='utf-8')
                    вади = згортання.згорнути(True)[1]
                    assert any('поле дата:' in п for п in вади) == (not свідомо), вади
                    assert any('поле дата-закриття:' in п for п in вади) == (bool(стан) and дата > '2026-10-30'), вади
        for дата in ('2026-10-26', '2026-10-31'):
            дошка.write_text(рядок('2026-10-26'), encoding='utf-8')
            фрагмент.write_text('стан 6977: ' + кінець.replace('механізм=інше;', f'дата={дата}; механізм=інше;'), encoding='utf-8')
            вади = згортання.згорнути(True)[1]
            assert not any('поле виявлено:' in п for п in вади), вади
            assert any('поле дата-закриття:' in п for п in вади) == (дата > '2026-10-30'), вади
        print('Дата появи: 8 сценаріїв; звичайна заміна зберігає, свідома виправляє; стан звіряє дату після заміни')
        print('Дата в статусі: джерело читається з цілого рядка; раннє закриття відхилено')
