"""Рука, що впала, у файл вердиктів не потрапляє: ні етапів, ні причини.

ДО (main на 26.09.2026): гілка `к.збій` ховає кнопку запису, чипів «Вдягнеш?» у
ній нема — отже `записати()` викликати нічим, і рядка в IndexedDB не з'являється.
ПІСЛЯ: кнопка так само схована (судити нема чого), а запис робить сам прогін —
`записатиЗбоїРукП` після шва збирання, полями `рука_впала` і `вердикт_жінки_нема`.
Друкує (1) гілку `к.збій` і шлях автозапису в показі, (2) скільки рук у прогонах
власника дійшло до файла (чотирирукий прогін: менше чотирьох — рука впала або не
судилась, і у старих файлах відрізнити це нема чим).
"""
import json
import pathlib

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
ПОКАЗ = (КОРІНЬ / "джерела" / "показ.html").read_text(encoding="utf-8")

рядки = ПОКАЗ.splitlines()
поч = next(i for i, р in enumerate(рядки) if "if (к.збій){" in р)
print("показ.html: гілка «рука не вимальовувалась» — рядки", поч + 1, "…", поч + 12)
for i in range(поч, поч + 12):
    т = рядки[i].strip()
    if "зап-" in т or "не-вийшло" in т or "чипРяд" in т:
        print("   ", i + 1, т[:150])
print("   чипів «Вдягнеш?» у цій гілці:", ПОКАЗ.count("чипРяд", поч, поч + 12),
      "→ вердикта жінки в цієї руки не буває за побудовою")
авто = next((i for i, р in enumerate(рядки) if "async function записатiЗбоїРукП" in р
             or "async function записатиЗбоїРукП" in р), None)
print("   автозапис збою в показі:", "нема" if авто is None else "показ.html:%d" % (авто + 1),
      "· кличеться з шва збирання:", ПОКАЗ.count("await записатиЗбоїРукП()"),
      "· полів у записі:", ", ".join(п for п in ("рука_впала", "вердикт_жінки_нема",
                                                 "запис_автоматичний", "ребра_чому")
                                     if п in ПОКАЗ) or "—")

тека = КОРІНЬ / "аудит" / "тести" / "власник_2026-09-25"
for ф in sorted(тека.glob("verdykty-*.json")):
    д = json.loads(ф.read_text(encoding="utf-8"))
    print(ф.name, "· прогонів", д["прогонів"], "· вердиктів", д["вердиктів"])
    for п in д["прогони"]:
        руки = sorted(в.get("рука", "?") for в in п["вердикти"])
        бракує = sorted({"1", "2", "3", "4"} - set(руки))
        збійних = [в for в in п["вердикти"] if в.get("збій") or в.get("вердикт_людини") is None]
        print("   розклад", п["спільне"].get("розклад"), "· руки у файлі", руки,
              "· нема", бракує or "—", "· записів «рука впала»", len(збійних))
