# -*- coding: utf-8 -*-
"""Приймальна проба Т-05: чи ВИКОНАНО правки другої ітерації — слово проти факту.

Друкує ФАКТИ на парі вердиктів `проби/виконання/` (до/після) і на відповіді моделі
між ними: `перевірено` кожної заявки, «невиконано», силу відхиленої знахідки. Рядок
«як доти» — це той самий вердикт, порахований БЕЗ попереднього вердикту, тобто рівно
те, що бачила модель до Т-05: `виконання` нема, «невиконано» нема, відхилена знахідка
йде повною силою — заявка «виправлено» над знахідкою, яка нікуди не зникла,
зараховувалась сама собою, бо її ніхто не звіряв.
Запуск із теки `джерела`: PYTHONPATH=. python3 проби/виконання_v1.py
"""
import json
import pipeline as PL, протокол as P

_ч = lambda ім: json.load(open("проби/виконання/%s.json" % ім, encoding="utf-8"))
до, відп, після = _ч("ВЕРДИКТ_до"), _ч("ОБРАЗИ_відповідь"), _ч("ВЕРДИКТ_після")
записи = [dict(номер=о["ід"], речі_н=о["речі"], підпис=о.get("підпис"), знахідки=о["знахідки"],
               блокери=(о.get("структура") or {}).get("блокери") or [],
               вузол=(о.get("вузол") or {}).get("назва"), рядок_вузла=(о.get("вузол") or {}).get("чому"))
          for о in після["образи"]]
сила = lambda вд, прав: [z["сила_нп"] for о in вд["образи"] for z in о["знахідки"] if z["правило"] == прав]
рядок = lambda вд: ("виконання %s · невиконано %s · K-PAL-07 (відхилена) %s · вимог %d · помилок схеми %d"
                    % ([[з["перевірено"] for з in (о.get("виконання") or [])] for о in вд["образи"]],
                       (вд.get("набір") or {}).get("невиконано"), сила(вд, "K-PAL-07"),
                       len(вд["завдання"]["вимоги"]), len(P.перевірити(P.СХЕМИ["ВЕРДИКТ_V1"], вд))))

print("як доти (без попереднього вердикту): %s" % рядок(PL.вердикт_v1(записи, варіантів=1, ітерація=2)))
вд = PL.вердикт_v1(записи, варіантів=1, випадок=після["випадок"], ітерація=2,
                   попередній_вердикт=до, відповідь_моделі=відп)
print("з Т-05:                              %s" % рядок(вд))
for о in вд["образи"]:
    for з in (о.get("виконання") or []):
        print("   %s %s → %s: %s" % (о["ід"], з["знахідка"], з["перевірено"], з["чому"]))
print("   повторна вимога: %s" % вд["завдання"]["вимоги"][-1])
