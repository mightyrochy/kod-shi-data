"""ОЦІНКА-1000: колір речі з ЩІЛЬНОЇ рамки моделі — без поля навколо й з полем (як тепер кадрить показ).
Кадр ф1 стенда (жакет хакі з блакитною сорочкою, спідниця) і рамки, які назвала жива Sonnet 02.10.
Друкує факт: що поміряв код у кожній рамці — до (кадр без поля) і після (поле 12 % + ядро)."""
import base64, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import річ_з_фото as РФ

W, H = 600, 800
ЖАКЕТ = [(170, 90), (430, 90), (480, 130), (480, 440), (430, 440), (430, 470), (170, 470), (170, 440), (120, 440), (120, 130)]
ФІГУРИ = [((0x7d, 0x7f, 0x63), ЖАКЕТ), ((0xcf, 0xd8, 0xe3), [(250, 110), (350, 110), (350, 400), (250, 400)]),
          ((0x6b, 0x1f, 0x2a), [(200, 520), (400, 520), (430, 760), (170, 760)])]
ТЛО = (0xef, 0xe9, 0xe1)

def всередині(x, y, п):
    ок = False
    for (ax, ay), (bx, by) in zip(п, п[1:] + п[:1]):
        if (ay > y) != (by > y) and x < (bx - ax) * (y - ay) / (by - ay) + ax:
            ок = not ок
    return ок

def піксель(x, y):
    к = ТЛО
    for колір, п in ФІГУРИ:
        if всередині(x + .5, y + .5, п):
            к = колір
    return к

def кадр(р, поле):
    л, в, п, н = р["left"], р["top"], р["right"], р["bottom"]
    dx, dy = (п - л) * поле, (н - в) * поле
    л2, в2, п2, н2 = max(0, л - dx), max(0, в - dy), min(1000, п + dx), min(1000, н + dy)
    x0, x1, y0, y1 = [round(a / 1000 * s) for a, s in ((л2, W), (п2, W), (в2, H), (н2, H))]
    к = min(1, 128 / max(x1 - x0, y1 - y0))
    w, h = max(1, round((x1 - x0) * к)), max(1, round((y1 - y0) * к))
    сирі = bytes(b for j in range(h) for i in range(w) for b in піксель(x0 + i / к, y0 + j / к))
    д = {"дані": base64.urlsafe_b64encode(сирі).decode(), "ширина": w, "висота": h}
    if поле:
        д["ядро"] = {"ліво": round((л - л2) / (п2 - л2) * 1000), "верх": round((в - в2) / (н2 - в2) * 1000),
                     "право": round((п - л2) / (п2 - л2) * 1000), "низ": round((н - в2) / (н2 - в2) * 1000)}
    return д

for назва, слово, р in (("жакет (намальовано #7d7f63)", "olive", dict(left=200, top=112, right=799, bottom=587)),
                        ("сорочка (намальовано #cfd8e3)", "light_blue", dict(left=417, top=137, right=583, bottom=499))):
    for поле in (0, .12):
        в = РФ.виміряти(кадр(р, поле), слово_моделі=слово, рамка=р)
        print("%-30s поле %-4s → %s" % (назва, поле, (в.get("hex"), в.get("слово")) if в.get("lab") else ("нема", в["чому"][:70])))
