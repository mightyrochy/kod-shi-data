"""Рядок 202, знахідка виконавиці рядка 208 (PR #296): на склеєному «мега-образі» (45 речей) ярус 4 ремонту
судив 1 260 варіантів — ~150 с на виклик. Стеля перебору — у речах, які судить суддя (`_СТЕЛЯ_РЕЧЕЙ_ПЕРЕБОРУ`).
Образи 6, 8, 12, 20, 45 речей із пулу театру (+14 °C, сід 3) — по k-тій речі кожного слота, тож дублі слотів є
завжди. ДО — та сама функція без стелі (стеля 10⁹, як main), ПІСЛЯ — як є. Друкує варіанти, секунди, чи повний,
і чи перебір обрізано. Звичайні образи — `проби/гейт_до_картки_202.py` (там варіантів ≤ 42, стеля не ріже).
Запуск: cd джерела && python3 проби/ярус4_стеля_202.py"""
import json, sys, os, time
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, повнота_образу as ПО
вх = dict(json.load(open("стенд_вх.json")), сценарій=dict(нагода="театр", місце="театр", година=19, темп_c=14,
          формат="змішано", рух="багато ходити"), випадок="театр", сід=3)
к = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["кандидати"]
СЛОТИ = ("верх", "низ", "взуття", "сумка", "прикраси", "верхній_шар", "сукня", "сережки", "шарф", "пояс", "браслет",
         "намисто", "головний_убір", "кольє", "каблучка", "брошка", "комплект")
усі = list(dict.fromkeys(к[с][i]["id"] for i in range(6) for с in СЛОТИ if len(к.get(с) or []) > i))
стеля = ПО._СТЕЛЯ_РЕЧЕЙ_ПЕРЕБОРУ
for n in (6, 8, 12, 20, 45):
    рядок = []
    for мітка, с in (("ДО", 10 ** 9), ("ПІСЛЯ", стеля)):
        ПО._СТЕЛЯ_РЕЧЕЙ_ПЕРЕБОРУ = с
        t = time.time()
        п = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=[усі[:n]], ітерація=2), ensure_ascii=False)))["повнота"]
        р = п.get("ремонт_гейтів") or {}
        рядок.append("%s: варіантів %4s · %5.1f с · повний %-5s%s" % (мітка, р.get("варіантів"), time.time() - t, п.get("повний"),
                     " · перебір обрізано на %s (відкинуто %s)" % (р["перебір_обрізано_на"], р["відкинуто_варіантів"])
                     if р.get("перебір_обрізано_на") is not None else ""))
    print("речей %2d │ %s" % (n, " │ ".join(рядок)))
ПО._СТЕЛЯ_РЕЧЕЙ_ПЕРЕБОРУ = стеля
