# -*- coding: utf-8 -*-
"""ВАГИ СЛОТІВ У КВОТАХ: чи обов'язковий слот сценарію завжди має місце в пулі.

`pipeline.структура_образу` блокує образ без верху й низу, `пакет_для_моделі`
пише моделі «обов'язкові слоти: взуття, сумка» — а пул ділив бюджет між усіма
слотами РІВНО, тож брошка важила стільки ж, скільки взуття. Проба друкує лічбу
речей НА СЛОТ для шести гілок стенда — тієї самої матриці, якою ходить
`тест_живого_шляху`: {гілка «не обирала», гілка 0} × {conventional,
fashion_forward, statement} на `каталог_brief.xml` (фід, що їде в артефакт).
ЩО БУЛО (e35eed0, до правки): на ВСІХ шести гілках «низ» давав 2 речі при 33
низах у каталозі — при поясі 29 і шарфі 29.
Провал — обов'язковий слот, порожній або з менш ніж `composer.МІН_ОБОВЯЗКОВОГО`
речами при непорожньому слоті каталогу.
Запуск: PYTHONPATH=. python3 проби/shvydkist_квоти.py
"""
import json
import sys, pathlib
_ДЖЕРЕЛА = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_ДЖЕРЕЛА))
import bridge as B
import composer as КМ
import feed as F

ДО = {"низ": 2, "верх": 7, "взуття": 22, "сумка": 20}   # гілка None, conventional
вх0 = json.load(open(_ДЖЕРЕЛА / "стенд_вх.json", encoding="utf-8"))
вх0["каталог"] = F.каталог_на_диску("каталог_brief.xml")
бід = 0
for гілка in (None, 0):
    for намір in ("conventional", "fashion_forward", "statement"):
        вх = dict(вх0, намір=намір)
        вх["гілка"] = гілка
        вих = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
        к = {с: len(v) for с, v in (вих.get("кандидати") or {}).items()}
        обов = B._обовязкові_слоти(вх["сценарій"], вих.get("паспорт"), к)
        бракує = [с for с in обов if к.get(с, 0) < КМ.МІН_ОБОВЯЗКОВОГО]
        бід += 1 if бракує else 0
        print("гілка %-4s намір %-16s пул %-4d · %s"
              % (гілка, намір, вих.get("пул_речей") or 0,
                 ", ".join("%s %d" % (с, к[с]) for с in sorted(к, key=lambda x: -к[x]))))
        print("     обов'язкові %s: %s"
              % (", ".join(обов),
                 ("усі ≥ %d" % КМ.МІН_ОБОВЯЗКОВОГО) if not бракує
                 else "⚠ БРАКУЄ — " + ", ".join(бракує)))
        for с in обов:
            нота = (вих.get("ноти_слотів") or {}).get(с)
            if нота and "ДОБРАНО" in нота:
                # нота слота буває складена (напр. «гілки на межі нема; …ДОБРАНО…»),
                # тож друкуємо саме ту її частину, яка про добір
                print("     %s: %s" % (с, нота[нота.index("слот ДОБРАНО"):][:96]))
print("було на гілці «не обирала»/conventional: %s"
      % ", ".join("%s %d" % (с, n) for с, n in ДО.items()))
print("гілок із бідним обов'язковим слотом: %d із 6" % бід)
