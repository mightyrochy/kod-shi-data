# -*- coding: utf-8 -*-
"""ВАГИ СЛОТІВ У КВОТАХ: чи обов'язковий слот сценарію завжди має місце в пулі.

`структура_образу` вимагає взуття й сумку, а ядро — верх+низ АБО сукню/комплект.
Квота ж ділила бюджет речей рівно між усіма слотами, і рідкісний слот (брошка,
каблучка) міг забрати місце в обов'язкового. Проба друкує лічбу речей НА СЛОТ
для шести гілок стенда — тієї самої матриці, якою ходить `тест_живого_шляху`:
{гілка «не обирала», гілка 0} × {conventional, fashion_forward, statement} на
`каталог_brief.xml` (це той фід, що їде в артефакт).
Провал — обов'язковий слот, порожній або з менш ніж МІН речами.
Запуск: PYTHONPATH=. python3 проби/shvydkist_квоти.py
"""
import json
import bridge as B

МІН = 3
ПОТРІБНІ = ("взуття", "сумка")
ЯДРО = (("верх", "низ"), ("сукня",), ("комплект",))   # хоч одна повна пара

вх0 = json.load(open("стенд_вх.json"))
вх0["каталог"] = "каталог_brief.xml"
бід = 0
for гілка in (None, 0):
    for намір in ("conventional", "fashion_forward", "statement"):
        вх = dict(вх0, намір=намір)
        вх["гілка"] = гілка
        вих = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
        к = {с: len(v) for с, v in (вих.get("кандидати") or {}).items()}
        бракує = [с for с in ПОТРІБНІ if к.get(с, 0) < МІН]
        if not any(all(к.get(с, 0) >= МІН for с in пара) for пара in ЯДРО):
            бракує.append("ядро(верх+низ|сукня|комплект)")
        бід += 1 if бракує else 0
        print("гілка %-4s намір %-16s пул %-4d · %s"
              % (гілка, намір, вих.get("пул_речей") or 0,
                 ", ".join("%s %d" % (с, к[с]) for с in sorted(к, key=lambda x: -к[x]))))
        print("     обов'язкові: %s"
              % ("УСІ НА МІСЦІ (≥%d)" % МІН if not бракує
                 else "⚠ БРАКУЄ — " + ", ".join(бракує)))
print("гілок із порожнім обов'язковим слотом: %d із 6" % бід)
