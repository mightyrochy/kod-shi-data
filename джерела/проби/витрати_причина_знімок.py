"""Проба: причина запуску, що йшов у мить знімка, не залежить від наявності cause.json (вивантажити.причина).

Друкує клас і джерело для трьох випадків; очікування — порожній клас у перших двох, клас cause.json у третьому.
Запуск: PYTHONUTF8=1 python3 джерела/проби/витрати_причина_знімок.py (з кореня репозиторію).
"""
import importlib.util
import pathlib

шлях = pathlib.Path(__file__).resolve().parents[2] / "аудит/витрати/токени_ноутбука_1211/вивантажити.py"
специф = importlib.util.spec_from_file_location("вивантаження", шлях)
м = importlib.util.module_from_spec(специф)
специф.loader.exec_module(м)

класи = {"STALL": "модель"}
запис = {"class": "модель", "text": "STALL"}
стан = {"code": "STALL"}
з = {"код": "НЕМАЄ_КОДУ", "стадія": "сесія моделі", "початок_UTC": "", "кінець_UTC": ""}
випадки = [
    ("іде у знімку, кінець пізніше, cause.json нема", з, стан, {}),
    ("іде у знімку, кінець пізніше, cause.json є", з, стан, запис),
    ("кінець у знімку, cause.json є", {**з, "код": "STALL"}, стан, запис),
]
for назва, запуск, st, зап in випадки:
    клас, текст, джерело = м.причина(запуск, st, зап, "", "", False, [], класи)
    print(f"{назва}: клас=«{клас}» джерело={джерело}")
