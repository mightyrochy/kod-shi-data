# -*- coding: utf-8 -*-
"""K-PAL-07 (колор-блок) — умова прийому судить образ.

Корпус (тема-2:1853): «2–3 сім'ї рівними площами; statement або високий контраст;
вимкнено на низькому під conventional» (Lamport: «unless heavy colour blocking»,
hint). `palettes.прийоми` це рахувало й вирішувало лише, чи називати прийом
доступним; що ОБРАЗ колор-блочить усупереч тому рішенню, не питав ніхто.
ПІСЛЯ: дві-три кольорові сім'ї у великих слотах при вимкненому прийомі дають
знахідку. Запуск із теки `джерела`: `python3 проби/pal_K-PAL-07.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import palettes as PAL, pipeline as PL

вх, r, кат, спец = ПВ.стенд(гілка=0)
П = спец["палітра_практична"]
акт = {x["прийом"] for x in П["прийоми"] if x["активний"]}
print("контраст «%s», намір «%s» → прийом «колор_блок» активний: %s"
      % (спец["палітра_практична"]["контраст_рівень"], "conventional", "колор_блок" in акт))
сім_я = lambda h: next((ім for ім, в in PAL.СІМ_Ї.items()
                        for a in (в.get("тепла"), в.get("холодна")) if a
                        and ((a[0] <= h <= a[1]) if a[0] <= a[1] else (h >= a[0] or h <= a[1]))), None)
кольоровий = lambda L, C, h, _: not PL._нейтральний_тон(h, C, L)
верх = ПВ.взяти(r, кат, "верх", кольоровий) or ПВ.з_каталогу(кат, "верх", кольоровий)
s_верх = сім_я(ПВ.lch(кат, верх["id"])[2]) if верх else None
# ДРУГА СІМ'Я — З КАТАЛОГУ: після правки вікон палітри пул однієї схеми тримає
# здебільшого одну сім'ю, а колор-блок — це рівно про дві. Модель може назвати
# річ поза пулом, і вердикт її судить.
низ = ПВ.з_каталогу(кат, "низ", lambda L, C, h, з: кольоровий(L, C, h, з) and сім_я(h) != s_верх)
решта = [ПВ.взяти(r, кат, с, lambda *a: True) for с in ("взуття", "сумка")]
print("великі слоти: верх «%s» (%s) · низ «%s» (%s)"
      % ((верх or {}).get("назва", "—")[:28], s_верх, (низ or {}).get("назва", "—")[:28],
         сім_я(ПВ.lch(кат, низ["id"])[2]) if низ else None))
ід = [x["id"] for x in [верх, низ] + решта if x]
зн, _ = ПВ.знахідки(вх, ід)
print("ФАКТ · K-PAL-07: %s" % ПВ.рядок(зн, "K-PAL-07"))
z = next((x for x in зн if x.get("правило") == "K-PAL-07"), None)
assert (z is not None) == (низ is not None and "колор_блок" not in акт), (bool(z), bool(низ), акт)
if z: print("       ремонт: %s" % z["ремонт"])
