# Рядок 6990: фактичні частки, джерело й контролі; шлях до очищеного XML — аргумент.
import os, sys, re
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from фід_верхнє import верхні_атрибути, _ПРО_ВОВНУ
from фід_атрибути import матеріал_речі
from feed import читати_yml

def частка(основа, **пар):
    """Читає частку справжнім читачем на контрольованій основі."""
    return верхні_атрибути({"назва": "Пальто", "параметри":
                          {"слот": "верхній_шар", "склад_основа": основа, **пар}}).get("вовна_частка")

if __name__ == "__main__":
    кат, _ = читати_yml(sys.argv[1])
    лічба = dict.fromkeys(("всього", "основа", "основа_кілька", "основа_проміжне", "кілька", "проміжне", "названо", "поріг"), 0)
    for о in кат:
        пар = о.get("параметри") or {}
        основа, _ = матеріал_речі(о)
        м = list(_ПРО_ВОВНУ.finditer(основа or ""))
        ч = верхні_атрибути(о).get("вовна_частка")
        лічба["всього"] += 1
        лічба["основа"] += bool(пар.get("склад_основа"))
        лічба["основа_кілька"] += bool(пар.get("склад_основа")) and len(м) > 1
        лічба["основа_проміжне"] += bool(пар.get("склад_основа")) and bool(re.search(r"вовн\w*\s+[^\W\d_]+\s+\d+\s*%", основа or ""))
        лічба["кілька"] += len(м) > 1
        лічба["проміжне"] += bool(re.search(r"(?<!ба)вовн\w*\s+[^\W\d_]+\s+\d+\s*%", основа or ""))
        лічба["названо"] += ч is not None
        лічба["поріг"] += ч is not None and ч >= .60
        if len(м) > 1 or (основа and "мериноса" in основа):
            print(о.get("id"), основа, "частка", ч)
    print(лічба)
    for с in ("10% мохер; 15% вовна; 15% поліамід; 60% вовна", "вовна мериноса 100%",
              "бавовна 100%", "невідомо", "110% вовна", "вовна 110%", "вовна 12,5%",
              "60% вовна; 60% вовна", "40% вовна; 60% поліестер", "вовна поліестер 40%", "59% вовна", "60% вовна",
              "18% vergin wool 60% merino wool 22% pe", "40% віскоза,40% вовна, 20% поліестер"):
        print("контроль", с, частка(с))
    print("підкладка", частка("100% віскоза", склад="100% віскоза; Підкладка: 100% вовна"))
    print("джерела не дублюються", частка("100% вовна", склад="100% вовна"))
