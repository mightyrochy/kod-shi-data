"""Друкує добір ДО за режимом і стабільність за замороженими SHA refs (7611)."""
import importlib.util
import pathlib

шлях = pathlib.Path(__file__).resolve().parents[2] / 'аудит/проби/живі_до.py'
опис = importlib.util.spec_from_file_location('живі_до', шлях)
м = importlib.util.module_from_spec(опис)
опис.loader.exec_module(м)
повне = '2. збирання (сід 3)\n2б. чотири картки за 10 с\nу мережу (FOTO=1)'
розмова = 'показ ПОВНИЙ\nНГ-4 · ВОНА: свято'
for назва, лог, факт in [('повне', повне, True), ('розмова', розмова, True),
                         ('повне', розмова, False), ('розмова', повне, False),
                         ('повне +фото', повне, True), ('повне +фото', повне.replace('(FOTO=1)', ''), False),
                         ('повне', 'показ ПОВНИЙ', None), ('функція', розмова, False)]:
    assert м.сумісний(назва, лог) is факт, (назва, лог)
print('режим: same, incompatible, missing, фото — очікувані відмови й збіги')
рефи = [('голова1', 'origin/claude/zhyvi-1'), ('голова2', 'origin/claude/zhyvi-2')]
м.рядки = lambda _: []
логи = {'голова1': повне, 'голова2': розмова}
def г(*а):
    """Імітує зміну гілок: читати артефакти дозволено лише за замороженим SHA."""
    if а[0] == 'ls-tree':
        assert а[-1] in логи
        return 'рез/код.txt'
    if а[0] == 'show':
        sha, ф = а[1].split(':', 1)
        assert sha in логи, 'читання рухомого ref замість SHA'
        return f'код{sha[-1]} сцена ПІСЛЯ модель' if ф.endswith('код.txt') else логи[sha]
    return '10' if а[0] == 'rev-list' else ''
м.г = г
до = м.добрати('сцена', 'кодПІСЛЯ', 'повне', рефи)
assert до[0][2] == 'код1' and до[1] == (0, 1, 0)
assert до == м.добрати('сцена', 'кодПІСЛЯ', 'повне', list(reversed(рефи)))
assert м.добрати('сцена', 'кодПІСЛЯ', 'функція', рефи)[0] is None
логи['голова1'] = ''
assert м.добрати('сцена', 'кодПІСЛЯ', 'повне', рефи)[1] == (0, 1, 1)
assert м.добрати('інша', 'кодПІСЛЯ', 'повне', рефи)[0] is None
print('добір: сумісний ДО; no candidate; missing mode; детермінізм сталого зрізу — PASS')
