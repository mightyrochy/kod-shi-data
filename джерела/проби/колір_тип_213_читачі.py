"""Рішення за межами доходять до суду аксесуарів, обличчя й рангу пулу."""
import sys
sys.path.insert(0, ".")
import аксесуари_структура as А, колір_нейтралі as Н, різноманітність_пулу as Р
import palettes as П


def головна():
    """Відрізнити доведений інтервал, неоднозначні межі та невідомий колір."""
    р = dict(id="інтервал", річ="намисто", слот="намисто", тип="намисто", метал="золото",
             lab=None, колір_тип="інтервал", нейтраль=None, near=1,
             колір_не_вимір=dict(слово="золотий", свідок="shop_word", вікно=(60, 80, 20, 60, (70, 100))))
    гучний = dict(річ="сумка", слот="сумка", lab=(60, 60, 0), near=1)
    метал = А.аксесуар_як_структура([р, гучний])
    черв = dict(р, річ="верх", слот="верх", метал=None, колір_не_вимір=dict(
        слово="червоний", свідок="shop_word", вікно=(50, 52, 55, 60, (40, 45))))
    бік = Н.бік_b_біля_обличчя([черв], {}, _бб=dict(вхід=True, бік=-1, b_очей=-10, довіра=1.0))
    пари = А.надточний_збіг([dict(черв, крамниця="а"), dict(черв, річ="сумка", слот="сумка", крамниця="б")])
    факт = dict(метал_знахідок=len(метал), бік=len(бік), пари=len(пари),
                хрома=Р._хрома(черв))
    print(факт)
    assert факт == dict(метал_знахідок=0, бік=1, пари=1, хрома=55)
    assert П.слоти_акценту_схеми([черв], {"верх": dict(роль="акцент")}) == {"верх"}
    нев = dict(черв, колір_тип="невідомо")
    assert not Н.бік_b_біля_обличчя([нев], {}, _бб=dict(вхід=True, бік=-1, b_очей=-10, довіра=1.0))
    assert not А.акцентні_поверхні([нев]) and Р._хрома(нев) == 0


if __name__ == "__main__":
    головна()
