# -*- coding: utf-8 -*-
"""ДО (main на 26.09.2026): навіть на ВДАЛОМУ виклику `запамʼятатиЗапит`/`етапВиклику`
кладе у звіт `символів: String(текст).length` і `фото: кількість` —
розмір лише ТЕКСТУ, а фото — лише ЛІЧБА, не байти. Справжній розмір, що рахує міст
(worker.js:283, `JSON.stringify(тіло.messages).length`), несе фото base64 повністю.
Тому колонка `символів` у звіті вердиктів (і опис 8352, і складання 8060, і
приміряння 7206-7278 — усі три шлють фото) завжди МЕНША за те, що йшло в модель.
Факт із файлу власника: рядок `виклики[0]` каже «складання … символів=119893 фото=1»
— а рядок `діагноз_руки` того ж вердикта каже про запит 428155 симв на тому самому
кроці. ПІСЛЯ (ділянка 6/8): `розмірЗапитуП` дає три числа — `символів` (текст, ключ V2 не
міняється), `фото_символів` (base64 знімків того ж тіла) і `разом_символів` (сума,
тобто вага тіла запиту). Проба перевіряє формулу в самому коді. Друкує факт.
Запуск: cd джерела && python3 проби/шлях_розмір_текст_без_фото.py"""
import os
показ = open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                          "показ.html"), encoding="utf-8").read()

формула = ("const т = String((з || {}).текст || '').length, ф = ((з || {}).фото_символів ?? 0);\n"
           "  return {символів: т, фото_символів: ф, разом_символів: т + ф};")
assert формула in показ, "формула розміру запиту змінилась — перевір `розмірЗапитуП` у показ.html"
print("розмірЗапитуП = символів (текст) + фото_символів (base64) = разом_символів")

сума_фото = "фото_символів: фф.reduce((а, ф) => а + String((ф && ф.дані) || '').length, 0)"
assert сума_фото in показ, "запамʼятатиЗапит більше не сумує байти фото — перевір показ.html"
print("запамʼятатиЗапит.фото_символів =", сума_фото.split(":")[1].strip()[:60], "— сума байтів, не лічба")

рахує_міст = "const розмір = JSON.stringify(тіло.messages || []).length;"
worker = open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                          "worker.js"), encoding="utf-8").read()
assert рахує_міст in worker, "міст рахує розмір інакше — перевір worker.js:283"
print("а міст рахує розмір за `%s` — увесь `messages`, разом із base64 фото" % рахує_міст.strip("; "))

реальний_текст, реальний_запит = 119_893, 428_155
print("на живому запиті власника звіт назвав %d символів, а поїхало %d (розбіжність ×%.1f)"
      % (реальний_текст, реальний_запит, реальний_запит / реальний_текст))
print("тим самим числом `разом_символів` це тепер і стоїть у файлі — саме воно зводиться з HTTP 413")
assert реальний_запит > 3 * реальний_текст
