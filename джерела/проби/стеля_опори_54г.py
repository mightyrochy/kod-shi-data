# лишається ТІЛЬКИ там, де еталон каже «текст має опору» (вердикт не «вигадано»): вигадані стають unknown — це межа для
# будь-якого кроку «чи цитата говорить про поле» на цій формі. Запуск: python3 проби/стеля_опори_54г.py <тека>/розбір.json
import sys, os, io, json, runpy, contextlib, collections
ТУТ = os.path.dirname(os.path.abspath(__file__))
шлях = sys.argv[1]
sys.argv = ['x', шлях]
буфер = io.StringIO()
with contextlib.redirect_stdout(буфер):
    g = runpy.run_path(os.path.join(ТУТ, 'еталон_частки.py'))
Е, ПОЛЯ = g['Е'], g['ПОЛЯ']
до, після = collections.defaultdict(collections.Counter), collections.defaultdict(collections.Counter)
for р in Е['речі']:
    в = р.get('вердикти', {}).get('нове')
    if not в or '_' in в:
        continue
    for п in ПОЛЯ:
        до[п][в[п]] += 1
        після[п]['невідомо' if в[п] == 'вигадано' else в[п]] += 1
def разом(л):
    с = collections.Counter()
    for п in ПОЛЯ:
        с.update(л[п])
    return с
for назва, л in (('ДО (V5 як є)', до), ('СТЕЛЯ (вигадані → unknown)', після)):
    с = разом(л)
    print('%s: правильно %d · хибно %d · вигадано %d · невідомо %d' % (назва, с['правильно'], с['хибно'], с['вигадано'], с['невідомо']))
    for п in ПОЛЯ:
        print('   %-10s п %2d х %2d м %2d в %2d' % (п, л[п]['правильно'], л[п]['хибно'], л[п]['невідомо'], л[п]['вигадано']))
з = [р for р in Е['речі'] if р.get('вердикти', {}).get('нове') and '_' not in р['вердикти']['нове']]
for назва, л in (('ДО', до), ('СТЕЛЯ', після)):
    всього = sum(л['slot'].values())
    print('slot «м» %s: %d з %d = %.0f%%' % (назва, л['slot']['невідомо'], всього, 100 * л['slot']['невідомо'] / max(1, всього)))
