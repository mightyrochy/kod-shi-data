# -*- coding: utf-8 -*-
"""Світле блакитне — колір; «вийшла» на слові — видно у звіті (рядок 1455).

(1) `колір_річ.нейтраль` (роль за сім'ями модуля, крок 26): світле блакитне — колір, як вжиток
каталогу (збагачення: h 230–300, L* ≥ 60, C* 12–24 — «блакитний» 100 %). (2) `несе_колір`: слово несе
колір межами вікна, не центром (рядок 3090). «Слово» — на слові, чиє вікно модуль зве кольором цілком
(«червоний», центр #d40047); межі «зеленого» лежать по обидва боки ролі модуля (olive) — «невідомо»: річ не
несе кольору й не нейтраль, хоч центр вікна (#39873a) — колір (рішення менеджера 08.11, 14005). Запуск із
`джерела`."""
import sys, pathlib, gzip, json, collections as K
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import колір_річ as КР, palettes as PAL, палітра_схеми as ПСХ, colorspace as cs, verify as V, фід_збагачення as ФЗ

зб = json.load(gzip.open("каталог_збагачення.json.gz", "rt"))
пох = K.Counter()
for v in зб.values():
    x = v.get("колір_основний") or {}
    if not КР.hex_кольору(x): continue
    L, C, h = cs.lch(cs.hx(КР.hex_кольору(x)))
    if 230 <= h <= 300 and L >= 60 and 12 <= C <= 24:
        пох[(x.get("слово"), "нейтраль" if КР.нейтраль(cs.hx(КР.hex_кольору(x))) else "колір")] += 1
print("каталог h 230–300, L* ≥ 60, C* 12–24 (слово, читання коду):", пох.most_common(4))
assert not any(ч == "нейтраль" for (_, ч) in пох), пох
for hx, ім in (("#b3d9ff", "Туфлі Sergio Rossi блакитні"), ("#2a3a5a", "нейві"), ("#9ba5b0", "блакитні джинси C7")):
    print("%s %s: %s" % (hx, ім, КР.нейтраль(cs.hx(hx)) or "колір"))
assert КР.нейтраль(cs.hx("#b3d9ff")) is None and КР.нейтраль(cs.hx("#2a3a5a")) == "холодна"

сп = {"сумка": dict(роль="акцент", C=[28.0, 70.0]), "_схема": "нейтрали+акцент"}
туфлі = [{"id": "t", "слот": "взуття", "hex": "#b3d9ff"}, {"id": "v", "слот": "верх", "hex": "#f2f2f2"}]
print("нейтрали+акцент, блакитні туфлі: картка «вийшла» =", "так" if not ПСХ.повідомлення_схеми_жінці(туфлі, сп) else "ні")
assert not ПСХ.повідомлення_схеми_жінці(туфлі, сп)
# слово несе колір межами вікна, не центром (рядок 3090, #1207): поле — як у запису фіду
def сумка(слово, hx):
    return {"id": "s", "слот": "сумка", "hex": hx, "колір_не_вимір": ФЗ.не_вимір_кольору(V.ЛЕКСИКОН[слово], слово, "shop_word")}
for слово, hx, свідок in (("червоний", "#d40047", "слово"), ("зелений", "#39873a", None)):
    сл = сумка(слово, hx)
    print("сумка «%s» %s (центр вікна слова): свідок = %s · нейтраль невідома = %s · виміряна — %s" % (
        слово, hx, PAL.несе_колір(сл), PAL.нейтраль_невідома(сл), PAL.несе_колір(dict(сл, колір_не_вимір=None))))
    assert PAL.несе_колір(сл) == свідок and PAL.несе_колір(dict(сл, колір_не_вимір=None)) == "вимір"
    assert PAL.нейтраль_невідома(сл) == (свідок is None)
