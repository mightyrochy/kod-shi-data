# -*- coding: utf-8 -*-
"""Світле блакитне — колір; «вийшла» на слові — видно у звіті (рядок 1455).

(1) `колір_річ.нейтраль`: холодний коридор при L* ≥ 60 не ширший за `neutral_C` — вжиток
каталогу (збагачення: h 230–300, L* ≥ 60, C* 12–24 — «блакитний» 100 %). (2) `_несе_колір`:
центр вікна слова (`колір_не_вимір`) — «слово», не «вимір». Запуск із `джерела`."""
import sys, pathlib, gzip, json, collections as K
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import колір_річ as КР, palettes as PAL, colorspace as cs

зб = json.load(gzip.open("каталог_збагачення.json.gz", "rt"))
пох = K.Counter()
for v in зб.values():
    x = v.get("колір_основний") or {}
    if not x.get("hex"): continue
    L, C, h = cs.lch(cs.hx(x["hex"]))
    if 230 <= h <= 300 and L >= КР.СВІТЛА_ХОЛОДНА_L and 12 <= C <= 24:
        пох[(x.get("слово"), "нейтраль" if КР.нейтраль(cs.hx(x["hex"])) else "колір")] += 1
print("каталог h 230–300, L* ≥ 60, C* 12–24 (слово, читання коду):", пох.most_common(4))
assert not any(ч == "нейтраль" for (_, ч) in пох), пох
for hx, ім in (("#b3d9ff", "Туфлі Sergio Rossi блакитні"), ("#2a3a5a", "нейві"), ("#9ba5b0", "блакитні джинси C7")):
    print("%s %s: %s" % (hx, ім, КР.нейтраль(cs.hx(hx)) or "колір"))
assert КР.нейтраль(cs.hx("#b3d9ff")) is None and КР.нейтраль(cs.hx("#2a3a5a")) == "холодна"

сп = {"сумка": dict(роль="акцент", C=[28.0, 70.0]), "_схема": "нейтрали+акцент"}
туфлі = [{"id": "t", "слот": "взуття", "hex": "#b3d9ff"}, {"id": "v", "слот": "верх", "hex": "#f2f2f2"}]
print("нейтрали+акцент, блакитні туфлі: картка «вийшла» =", "так" if not PAL.повідомлення_схеми_жінці(туфлі, сп) else "ні")
assert not PAL.повідомлення_схеми_жінці(туфлі, сп)
сл = {"id": "s", "слот": "сумка", "hex": "#39873a", "колір_не_вимір": {"слово": "зелений"}}
print("сумка «зелений» #39873a (центр вікна слова): свідок =", PAL._несе_колір(сл), "· виміряна — ", PAL._несе_колір(dict(сл, колір_не_вимір=None)))
assert PAL._несе_колір(сл) == "слово" and PAL._несе_колір(dict(сл, колір_не_вимір=None)) == "вимір"
