"""Оцінка: кожне правило — спільним контрактом серед її речей; склад іншої довжини судиться (12976, 12979)."""
import sys
from pathlib import Path
from unittest.mock import patch
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import оцінка_образу as О, пропозиція_заміни as П


def головна():
    """Друкує факти: зміна на правило, сукня замість двох речей, суд складу раз, додавання й вилучення."""
    зн = lambda правило, річ: dict(правило=правило, суть="вимір", речі=[річ], сила_нп=0.5)
    речі = [dict(ід=і, слот=с) for і, с in (("ф0", "верх"), ("ф1", "низ"), ("ф2", "взуття"), ("с1", "верх"), ("с0", "сукня"))]
    суди = []
    def ваги(ід, *_):
        """Знахідки за складом: K-A на верху ф0, K-B на низу ф1; сукня знімає обидві."""
        суди.append(tuple(ід)); с = {і.split("-")[-1] for і in ід}
        return dict(знахідки=[зн("K-A", "її-ф0")] * ("ф0" in с) + [зн("K-B", "її-ф1")] * ("ф1" in с))
    with patch.object(О, "_ваги_образу", ваги), patch.object(О._СЧ, "відсутнє_на_фото", lambda о, *_: (о, [])):
        о0 = ваги(["її-ф0", "її-ф1", "її-ф2"]); суди.clear()
        зміни, звіт = О.зміни({}, {}, {}, {}, речі, ["ф0", "ф1", "ф2"], ["с1", "с0"], о0, {})
    assert [(з["знято"], з["образ"]) for з in зміни] == [(["K-A"], ["с1", "ф1", "ф2"]), (["K-B"], ["с0", "ф2"])]
    assert зміни[1]["складові"] == [dict(ціль="ф0", нова="с0"), dict(ціль="ф1", нова="с0")]
    assert len(суди) == len(set(суди)) and not any("сума" in з or "дельта" in з or з["звідки"] != "own" for з in зміни)
    а, б = dict(id="а", слот="верх"), dict(id="б", слот="шар")
    межі, виклики = {"а": а, "б": б}, []
    def суд(склад):
        """Зауваження K-L тримається, доки в образі нема шару."""
        виклики.append([р["id"] for р in склад])
        return dict(знахідки=[] if len(склад) == 2 else [зн("K-L", "а")])
    додати = П.перевірити([а], [зн("K-L", "а")], [[а, б]], межі, [], суд, суд([а]))
    прибрати = П.перевірити([а, б], [зн("K-L", "а")], [[а]], межі, [], суд, dict(знахідки=[зн("K-L", "а")]))
    assert додати["заміни"] == [dict(було=None, стало="б")] and прибрати["образ"] is None and len(виклики) == 3
    print("Правил", звіт["правила"], "змін", len(зміни), "судів складу", len(суди), "без повторів;",
          "додавання 1→2: прийнято; вилучення 2→1: суджено, відхилено (K-L лишилось)")


if __name__ == "__main__":
    головна()
