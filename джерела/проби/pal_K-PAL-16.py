"""K-PAL-16 (контекст втягує межовий колір) — «без сліду» розібрано.

Аудит: «є в коді, на живому шляху не виконується». Гілка ЖИВА і підключена
(`композитор_оцінка` → `palettes.контекст_втягує`, а вона стоїть просто на шляху
`перевірити_від_моделі`). Мовчить вона через ВХІД, і корпус це передбачив дослівно:
«Inactive when the person's hue side is unknown (uncontrolled photo without
self-report)». На стенді вісь тону утримана (K-PC-05: підтон із неконтрольованого
фото не стверджується), `позиція.hue` = 0.00, і перша ж умова повертає порожньо.
ПІСЛЯ: (1) чекліст палітри, пункт P6, стоїть «без входу» — вимкнене більше не
вдає пройдене; (2) на стенді із самозвітом («срібло» → холодний бік) бік стає
відомим, і правило говорить.

ПРОБА ВИПРАВЛЕНА 27.09.2026 (П-5): доти вона брала компаньйонів ПЕРШИМИ З ПУЛУ, а
пул — це вже відповідь палітри, тож компаньйони виходили того самого боку, що й
людина. `контекст_втягує` на це дає ПОЗИТИВНУ силу («тримають — не міняй їх»), а
`композитор_оцінка` позитивний випадок у вердикт не пускає навмисно (17.09.2026:
схвалення — порада, а не вада образу; негативна вага гинула під підлогою). Тобто
проба вимагала від коду того, що власник із коду прибрав, і падала на зеленому
main. Тепер компаньйони беруться з КАТАЛОГУ протилежним боком (b* тепле проти
холодної людини) — рівно той вхід, на який правило звітує, — а позитивний випадок
міряється поруч і лишається поза вердиктом.
Запуск із теки `джерела`: `python3 проби/pal_K-PAL-16.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import palettes as PAL, суд_образу as СО, bridge as B, реєстр_правил as РП, json

_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
for самозвіт, мітка in ((None, "фото, вісь утримано"), ({"метал": "срібло"}, "самозвіт «срібло»")):
    вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
    if самозвіт: вх["самозвіт"] = самозвіт
    F = B._features(вх)[0]          # `_features` віддає кортеж; риси — перший елемент
    ос = PAL.осі(F, "uncontrolled", самозвіт)
    вхп = СО.входи_палітри(F, "uncontrolled", самозвіт)
    print("%-22s вісь тону %+.2f («%s») · вхід «бік температури»: %s"
          % (мітка, ос["позиція"]["hue"], ос["словами"]["hue"], вхп.get("бік_температури")))

# ГІЛКА ЗІ ЗНАЙОМИМ БОКОМ: межова річ (частка вікна < `_МЕЖОВА_ЧАСТКА`) із пулу —
# лише пул несе `_частка_вікна`, — а компаньйони з КАТАЛОГУ протилежним боком.
вх, r, кат, спец = ПВ.стенд(гілка=0, самозвіт={"метал": "срібло"})
межова = next((x for с in ("верх", "сукня", "низ")
               for x in (r["кандидати"].get(с) or [])
               if (x.get("частка_вікна") or 1.0) < PAL._МЕЖОВА_ЧАСТКА), None)
print("межова річ у пулі (частка вікна < %.2f): %s"
      % (PAL._МЕЖОВА_ЧАСТКА, ((межова or {}).get("назва") or "нема")[:44]))
_b_тепле = РП.C["b_нейтралі"][0] + 8      # явно за межею теплого боку нейтралі
чужі = [ПВ.з_каталогу(кат, с, lambda L, C, h, з: з["lab"][2] > _b_тепле)
        for с in ("взуття", "сумка", "низ")]
свої = [ПВ.взяти(r, кат, с, lambda *a: True) for с in ("верх", "низ", "взуття")]
for мітка, комп in (("компаньйони ПРОТИЛЕЖНОГО боку", чужі), ("компаньйони СВОГО боку (з пулу)", свої)):
    ід = [x["id"] for x in ([межова] if межова else []) + [y for y in комп if y]][:4]
    зн, вм = ПВ.знахідки(вх, ід)
    z = next((x for x in зн if x.get("правило") == "K-PAL-16"), None)
    print("ФАКТ · %-31s K-PAL-16: %s" % (мітка, ПВ.рядок(зн, "K-PAL-16")))
    пал = (((вм.get("вердикт") or {}).get("образи") or [{}])[0].get("чекліст") or {}).get("палітра") or {}
    print("       чекліст палітри: провалів %d · пройдено %s · без входу %s"
          % (len(пал.get("провал") or []), пал.get("пройдено"), пал.get("без_входу")))
    assert пал and (пал.get("без_входу") or 0) >= 1, "без входу не названо — вимкнене вдає пройдене"
    if комп is чужі:
        assert z, ("бік названий, межова річ у образі є, компаньйони протилежного боку — "
                   "а правило мовчить: перевір `композитор_оцінка` і самозвіт у сценарії вердикту")
        assert (z.get("сила_нп") or 0) > 0, z
    else:
        # СХВАЛЕННЯ У ВЕРДИКТ НЕ ЙДЕ НАВМИСНО (композитор_оцінка, 17.09.2026)
        assert z is None, ("позитивний випадок K-PAL-16 доїхав у вердикт: %s" % z)
