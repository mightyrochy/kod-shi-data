"""ФОКУС-2 (рядки 1460, 1461): `python3 проби/фокус_2.py` — чи суд велить ремонтом зняти колір,
який корпус не велить знімати. Образи з речей каталогу, вердикт — тим самим ендпойнтом, що продукт."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ, pipeline as PL
вх, r, кат, спец = ПВ.стенд(гілка=0, самозвіт={"метал": "золото"})
гучна = lambda h0, д=20: (lambda L, C, h, з: C >= 45 and not PL._нейтральний_тон(h, C, L)
                          and min(abs(h - h0), 360 - abs(h - h0)) <= д)
тиха = lambda L, C, h, з: C < 8 and 25 < L < 80
сумка = ПВ.з_каталогу(кат, "сумка", гучна(140))          # зелена
тон = ПВ.lch(кат, сумка["id"])[2]
кольє = (ПВ.з_каталогу(кат, "прикраси", гучна(тон, 15)) or ПВ.з_каталогу(кат, "шарф", гучна(тон, 15)))
червоні = ПВ.з_каталогу(кат, "взуття", гучна(25))
тло = [ПВ.з_каталогу(кат, с, тиха) for с in ("верх", "низ")]
def суд(*речі):
    зн, _ = ПВ.знахідки(вх, [x["id"] for x in речі if x])
    заяви = {(z.get("правило"), next(iter(з)) if isinstance(з, dict) and "code" not in з else з.get("code"))
             for z in зн for з in (z.get("заяви") or [])}
    ремонт = {z.get("правило"): [x.get("code") for x in (z.get("ремонт_заяви") or [])] for z in зн}
    return заяви, ремонт
for назва, речі in (("відлуння: сумка %.0f° + %s %.0f°" % (тон, кольє["слот"], ПВ.lch(кат, кольє["id"])[2]),
                     тло + [сумка, кольє]),
                    ("два гучні: зелена сумка + червоні туфлі %.0f°" % ПВ.lch(кат, червоні["id"])[2],
                     тло + [сумка, червоні])):
    заяви, ремонт = суд(*речі)
    гучно = ("K-PAL-15", "more_than_one_loud_colour") in заяви
    print("ФАКТ · %s → K-PAL-15 «гучних більше одного»: %s · ремонт K-PAL-15: %s · K-PAL-02: %s ремонт %s · "
          "K-ACC-01: %s ремонт %s" % (назва, "так" if гучно else "ні", ремонт.get("K-PAL-15"),
                                      "є" if "K-PAL-02" in ремонт else "нема", ремонт.get("K-PAL-02"),
                                      "є" if "K-ACC-01" in ремонт else "нема", ремонт.get("K-ACC-01")))
    if назва.startswith("відлуння"):
        assert not гучно, "відлуння одного тону лічиться двома гучними кольорами"
    for п in ("K-PAL-02", "K-ACC-01") + (("K-PAL-15",) if гучно else ()):
        assert not ремонт.get(п), "%s велить ремонт, якого корпус не просить: %s" % (п, ремонт[п])
