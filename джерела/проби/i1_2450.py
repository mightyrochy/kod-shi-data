"""Проба (рядок 2450): i1 (`суд_інтерес.тихі_джерела`) — контраст КЛАСІВ поверхні, а не будь-яких
двох кодів. (1) покриття: кожен код волокна (`verify.ВОЛОКНА`) і фактури каталогу має клас у
`КЛАС_ПОВЕРХНІ` — інакше він сам собі клас і дає «контраст» з усім; (2) на образах рук 1–2
збережених прогонів (база `тихі_1850.py`): скільки мають i1, які пари класів, і провали B1
(K-INT-04, conventional) окремо поза трауром і на траурі. Червоне — непокритий код.
Моделі не кличе. Запуск: python3 джерела/проби/i1_2450.py"""
import collections, glob, gzip, os, re, sys                                   # noqa: E401
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ)
import фід_каталог as ФК, композитор_річ as КР, outfit as O, verify as V        # noqa: E401,E402
import суд_інтерес as СІ                                                      # noqa: E402
кат = ФК._прочитати_каталог(ФК.каталог_на_диску(), ліміт_фото=0)["каталог"]
коди = {СІ.поверхня_речі(dict(волокно=в)) for в in V.ВОЛОКНА.values()} | {r["текстура"] for r in кат if r.get("текстура")}
непокриті = sorted(к for к in коди if к not in СІ.КЛАС_ПОВЕРХНІ)
print("кодів поверхні: %d · без класу: %s — %s" % (len(коди), непокриті or "—", "ЧЕРВОНЕ" if непокриті else "зелене"))
за_ід = {r["id"]: r for r in кат}
набори = {}
for ф in sorted(glob.glob(os.path.join(ТУТ, "..", "аудит", "перевірки", "**", "вердикти*.gz"), recursive=True)):
    for м in re.finditer(r'\\?"ід\\?": ?\[([^\]]*)\]', gzip.open(ф).read().decode()):
        ід = tuple(sorted(set(re.findall(r'ж-[^"\\,]+', м.group(1)))))
        if len(ід) >= 2 and all(і in за_ід for і in ід):
            набори.setdefault(ід, "похорон" in ф)
рах, пари = collections.Counter(), collections.Counter()
for ід, траур in набори.items():
    E = O.елементи([КР._у_річ(за_ід[і], за_ід[і]["слот"], None) for і in ід])
    к = "траур" if траур else "поза трауром"
    i1 = [д["важелі"][0][3:] for д in СІ.тихі_джерела(E) if д["важелі"][0].startswith("i1:")]
    рах[к] += 1
    рах[к, "i1"] += bool(i1)
    рах[к, "B1 провал"] += bool(СІ.підлога_інтересу_проактивно(E, "conventional", тихо=траур))
    пари.update(i1)
for к in ("поза трауром", "траур"):
    print("%s: образів %d · з i1 %d · B1 провал %d" % (к, рах[к], рах[к, "i1"], рах[к, "B1 провал"]))
print("пари класів i1:", ", ".join("%s %d" % кв for кв in пари.most_common(8)))
