"""Колірна реконструкція випадку вершниці без фото: повний суд і пропозиція або пояснення."""
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import оцінка_образу as О, річ_з_фото as Р, colorspace as К


def головна():
    """Звіряє шлях змін оцінки на кодах речей із паспорта й профілі стенда: кожна зміна знімає своє правило."""
    F, T, d = О.профіль(json.loads(Path("стенд_вх.json").read_text(encoding="utf-8")))
    сцен, _ = О._сцена({}, d)
    види = [("верх", "turtleneck", "#ffffff"), ("верхній_шар", "biker_jacket", "#111111"),
            ("низ", "trousers", "#3d291f"), ("взуття", "boots", "#94734f"),
            ("верх", "turtleneck", "#d8cbb5"), ("верхній_шар", "biker_jacket", "#94734f")]
    речі = [dict(ід="ф" + str(н), слот=с, вид=в, вимір=dict(hex=к, lab=К.hx(к)))
            for н, (с, в, к) in enumerate(види, 1)]
    образ, запасні = [р["ід"] for р in речі[:4]], [р["ід"] for р in речі[4:]]
    def суд(ід):
        """Перевіряє цілий образ тим самим судом, що й оцінка."""
        кат = [Р.запис_каталогу(dict(р, закріплена=True)) for р in речі if р["ід"] in ід]
        return О._СЧ.відсутнє_на_фото(О._ваги_образу([з["id"] for з in кат], кат, F, T, сцен, None), [],
                                      {з.get("слот") for з in кат})[0]
    до = суд(образ)
    # K-CLR-02 на профілі стенда на `main` b92baff4 не спрацьовує (рядок 13564): проба судить решту правил тим самим шляхом
    assert any((з.get("сила_нп") or 0) > 0 for з in до["знахідки"])
    assert not any(з.get("ремонт") or з.get("ремонт_заяви") or з.get("запит_у_каталог")
                   for з in до["знахідки"] if з.get("правило") == "K-CLR-02")
    зміни, звіт = О.зміни({}, F, T, сцен, речі, образ, запасні, до, {})
    for зміна in зміни:
        після = суд(зміна["образ"])
        assert not any(з.get("правило") in зміна["знято"] and (з.get("сила_нп") or 0) > 0 for з in після["знахідки"])
        дріт = О.зміни_для_моделі(dict(зміни=[зміна]))[0]
        assert len(дріт["replace"]) == len(зміна["складові"]) and дріт["together"]
        assert set(зміна["образ"]) <= set(образ + запасні) and зміна["звідки"] == "own"
    assert зміни or звіт["пояснення"]
    print("Профіль стенда, коди паспорта: пропозицій", len(зміни), "спільна зміна", [з["складові"] for з in зміни],
          "пояснення", звіт.get("пояснення"))


if __name__ == "__main__":
    головна()
