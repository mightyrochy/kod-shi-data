"""K-KOH-08 (табу гостя: біле на чужому весіллі): `python3 проби/koh_K-KOH-08.py`.

ЗВЕДЕННЯ ДАЄ «ЛИШЕ СЛІД», І ЦЕ ВИМІР БАТАРЕЇ, А НЕ ПРАВИЛА: емітент повний
(`формальність.нагода_палітра`), але вмикається лише на нагодах, чия картка несе
`вето_майже_біле` — тобто на весіллі гостем. Стенд і вся батарея ходять на нагоді
«робота», де правила цього немає за побудовою.
ЩО ПОКАЗУЄ ПРОБА: та сама майже-біла сукня на нагоді «весілля_гість» дає рядок
K-KOH-08 у вердикті й не дає його на «роботі»; і другий бік правила — стеля
гучності («не перевершити господиню») — живе там само."""
import sys, pathlib, json
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import feed as Ф, bridge as B, colorspace as КС

вх = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml"); вх["гілка"] = 0
вх["сценарій"].update(нагода="весілля_гість", місце="весілля_вечірнє", година=18)
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
білі = [c for c in кат if c.get("слот") == "сукня" and c.get("lab")
        and КС.lch(c["lab"])[0] >= 85 and КС.lch(c["lab"])[1] <= 12]
print("майже-білих суконь у каталозі пакета:", len(білі))
ціль = білі[0]; вз = next(c for c in кат if c.get("слот") == "взуття")
print("сукня:", ціль["назва"][:46], "· L*%.0f C*%.0f" % КС.lch(ціль["lab"])[:2])
for підпис, сцен in (("весілля_гість", dict(нагода="весілля_гість", місце="весілля_вечірнє")),
                     ("робота", dict(нагода="робота", місце="офіс"))):
    в = json.loads(json.dumps(вх, ensure_ascii=False)); в["сценарій"].update(сцен)
    вм = json.loads(B.виклик("від_моделі", json.dumps(
        dict(в, ід=[ціль["id"], вз["id"]]), ensure_ascii=False)))
    о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
    з = next((z for z in (о.get("знахідки") or []) if z["правило"] == "K-KOH-08"), None)
    print("%-16s K-KOH-08:" % підпис, "НЕМА" if not з else
          "%s %.2f · %s" % (з["сила"], з["сила_нп"], з["суть"][:44]))
