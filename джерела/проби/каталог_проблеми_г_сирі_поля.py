# -*- coding: utf-8 -*-
"""Рядок 5625 (реєстр 5616, клас Г6): збирання сторінок кладе в каталог сирий текст сторінки без меж блоку.
Факт: скільки різних назв `param`, яка частка сирих «~»-полів, ключі-речення, «~Колір» зі зліпленим розміром чи
таблицею, кілька «~Колір» на річ і ключі з блоків відгуків/оплати. Запуск: python3 джерела/проби/каталог_проблеми_г_сирі_поля.py"""
import collections, gzip, os, re                                               # noqa: E401
К = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
xml = gzip.open(os.path.join(К, "каталог_повний.xml.gz"), "rt", encoding="utf-8").read()
офери = re.findall(r"<offer\b.*?</offer>", xml, re.S)
пари = [(о, re.findall(r'<param name="([^"]*)">([^<]*)<', о)) for о in офери]
імена = collections.Counter(к for _, п in пари for к, _ in п)
сирі = sum(ч for к, ч in імена.items() if к.startswith("~"))
print("речей %d · param усього %d, з них сирих «~» %d (%.0f %%) · різних назв param %d (сирих %d)" % (len(офери),
      sum(імена.values()), сирі, 100 * сирі / sum(імена.values()), len(імена), sum(1 for к in імена if к.startswith("~"))))
речення = [к for к in імена if len(к) > 40 or re.search(r"[.:!?]\s*$", к)]
print("назв-речень (довше 40 знаків чи з крапкою/двокрапкою наприкінці): %d · на %d записах · %s" % (len(речення),
      sum(імена[к] for к in речення), [к[:50] for к, _ in collections.Counter({к: імена[к] for к in речення}).most_common(4)]))
кол = [(о, [з for к, з in п if к == "~Колір"]) for о, п in пари]
кілька = sum(1 for _, з in кол if len(з) > 1)
зліплено = sum(1 for _, з in кол if any(re.search(r"Розмір|Таблиц|онлайн", х) for х in з))
print("«~Колір» на %d речах · кілька значень на одній речі %d · значення зі зліпленим «Розмір/Таблиця» %d" % (
      sum(1 for _, з in кол if з), кілька, зліплено))
службові = {к: ч for к, ч in імена.items() if re.search(r"Оплат|Доставк|Відгук|Швидкий перегляд|бонус|Купити", к)}
print("ключі з блоків оплати/доставки/відгуків/швидкого перегляду: %d назв, %d входжень · %s" % (len(службові),
      sum(службові.values()), sorted(службові, key=службові.get, reverse=True)[:4]))
опис_хвіст = sum(1 for о, п in пари for к, з in п if к == "опис" and re.search(r"(Весь опис|Читати далі|Показати більше)\s*$", з))
print("«опис», що кінчається кнопкою сторінки («Весь опис», «Читати далі»…): %d" % опис_хвіст)
