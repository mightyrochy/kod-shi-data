"""Виходи писарів, походження й незалежність значення та уривка одного факту."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import картка_запиту as к
import паспорт_нагоди as п
from паспорт_основи import типові_з_форми

паспорт = {}
к.записати(паспорт, 'місце', 'парк', 'her', 'у парку')
к.дотики(паспорт, [dict(поле='місце', значення='офіс', джерело='hand')])
assert к.факт(паспорт, 'місце') == dict(значення='офіс', джерело='hand', уривок='')
assert 'місце' not in паспорт['цитати_полів']
for відповідь in ('', 'не JSON', '{}'):
    після = п.паспорт_з_json(відповідь, {}, '', паспорт_досі=паспорт)
    assert к.факт(після, 'місце') == к.факт(паспорт, 'місце')
    assert після['місце'] == 'офіс'
к.записати(паспорт, 'місце', 'парк', 'reading', 'інший уривок')
assert паспорт['місце'] == 'офіс' and 'місце' not in паспорт['цитати_полів']
межі = {'зони': ['руки']}
к.записати(паспорт, 'вето', межі, 'hand')
межі['зони'].append('спина')
паспорт['вето']['зони'].append('ноги')
assert к.факт(паспорт, 'вето')['значення'] == {'зони': ['руки']}
к.записати(паспорт, 'година', 11, 'default')
паспорт['джерело_полів'] = {'година': 'her', 'темп_c': 'form_default'}
assert 'година' in типові_з_форми(паспорт)
к.записати(паспорт, 'темп_c', 0, 'hand')
assert 'темп_c' not in типові_з_форми(паспорт)
після = п.паспорт_з_json('{"нагода":"театр"}', {}, '')
assert к.факт(після, 'нагода')['джерело'] == 'reading'
assert к.факт(після, 'нагода')['уривок'] == ''
print('Обидва виходи: факт збережено; чужих уривків: 0; типове не стає її словом; копії незалежні.')
