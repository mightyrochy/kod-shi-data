"""Діагноз у файлі може належати ІНШОМУ прогону, ніж картка, на яку його записано.

`етапиЗапису` бере рядки діагнозу з ГЛОБАЛЬНОГО `ЗБ` — стану ОСТАННЬОГО збирання,
а не того прогону, з якого картка. Відкрила образ із бібліотеки → вердикт поніс
чужий діагноз, а разом із ним `чат`, `вхід_прогону`, `поломка`, `пул_спільних`.
Друкує доказ із файла власника: рука, що `виконано: усе` й має 4 свої виклики,
несе діагноз про запит на 428 155 символів, якого серед її викликів нема.
"""
import json
import pathlib
import re

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
ф = КОРІНЬ / "аудит" / "тести" / "власник_2026-09-25" / "verdykty-0phxvk-2026-09-25-2012.json"
д = json.loads(ф.read_text(encoding="utf-8"))

for п in д["прогони"]:
    for в in п["вердикти"]:
        діагноз = (в.get("етапи") or {}).get("діагноз_руки") or []
        if not діагноз:
            continue
        виклики = (в.get("етапи") or {}).get("виклики") or []
        симв = [(в2.get("крок"), (в2.get("запит") or {}).get("символів")) for в2 in виклики]
        print("розклад", п["спільне"].get("розклад"), "· рука", в.get("рука"),
              "· виконано:", в.get("виконано"), "· викликів", в.get("викликів"))
        for р in діагноз:
            print("   діагноз:", р[:160])
            for ч in re.findall(r"\b(\d{6,})\b", р):
                є = [к for к, с in симв if с == int(ч)]
                print("      запит на", ч, "символів серед викликів руки:", є or "НЕМА")
        print("   свої виклики:", симв)

ПОКАЗ = (КОРІНЬ / "джерела" / "показ.html").read_text(encoding="utf-8")
for н, р in enumerate(ПОКАЗ.splitlines(), 1):
    if "ЗБ && ЗБ.діагноз" in р or "ЗБ.вхід" in р or "ЗБ && ЗБ.чат" in р:
        print("показ.html:%d" % н, р.strip()[:110])
