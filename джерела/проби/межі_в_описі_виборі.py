"""Знахідка ноутбука 25.09 («#323 наживо», main s7, рука 1): опис назвав мюлі на підборах «компромісом»
при її «без підборів» — меж жінки у вході опису й вибору не було. Проба: паспорт із вето «підбори»
крізь справжній міст → чи стоїть поле «межі» (і його рядок) у промпті вибору й опису. Моделі не кличе.
Запуск: cd джерела && python3 проби/межі_в_описі_виборі.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B
міст = lambda ім, **в: json.loads(B.виклик(ім, json.dumps(в, ensure_ascii=False)))
СЛОВА = "робочий день в офісі, дрес-код business casual, без підборів"
ВЕТО = dict(типи=["підбори"], тканини=[], принти=[], кольори=[], зони=[])
п = міст("паспорт", сценарій={}, вимоги=СЛОВА, json_моделі=json.dumps(dict(
    подія="робочий день в офісі", нагода="робота", місце="офіс_корпоративний", дрес_код="business_casual",
    намір="conventional", вето=ВЕТО), ensure_ascii=False))
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), варіантів=10, ремонт_варіантів=5, бюджет_символів=120000,
          без_фото=1, сценарій={}, вимоги=СЛОВА, паспорт=п["паспорт"], випадок=п["випадок"])
print("вето паспорта:", (п["паспорт"].get("вето") or {}).get("типи"))
r = міст("запити", **вх); пул = json.loads(r["руки"]["1"])["пул"]; н = lambda с, k: пул[с][k % len(пул[с])]["н"]
образи = [dict(ід="о%d" % (і + 1), підпис="задум %d" % і, речі=[н("верх", і), н("низ", і), н("взуття", і), н("сумка", і)])
          for і in range(4)]
в = міст("від_моделі", текст_моделі=json.dumps(dict(версія="1", образи=образи), ensure_ascii=False), **вх)
for ім, т in (("вибір", в.get("промпт_лише_вибору")),
              ("опис", міст("опис", **dict(вх, речі=[сл[0]["id"] for сл in r["кандидати"].values() if сл][:5]))["промпт"])):
    об = json.loads(т); рядок = [x for x in об["завдання"]["вхід"] if x.startswith("«межі»")]
    print("%-6s поле «межі»: %s · рядок: %s" % (ім, об.get("межі"), рядок[0][:90] if рядок else "НЕМА"))
