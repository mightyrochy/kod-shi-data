"""КОЛО-3, рядок 1870: місця опор `_КОЛО` для третин. ДО — 6 опор (мідь 45°, тіл 225°); ПІСЛЯ —
мідь і тіл на RO 30°/BG 210° і пара B 240° (медіана «блакитний») ↔ O 60° (лінія мідь–кемел). Міри:
(1) взірець власниці «оливковий, блакитний, бордовий» — тріада з кожного якоря (відхил ≤25° — суд
K-PAL-03 приймає); (2) комплементи медіан каталогу проти пар корпусу (K-COL-03 §4) — не гірше;
(3) місця основних слів каталогу на колі проти 12-кольорового кола (R 0, O 60, Y 120, G 180, B 240, V 300);
(4) лупа: градусів кола на 1° тону CIELAB біля карих очей і волосся (h50–65).
Тони — медіани тону речей каталогу зі словом (C*>8). Запуск із `джерела` (потрібен повний каталог)."""
import sys, pathlib, math, collections
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import feed as F; F.каталог_на_диску('каталог_повний.xml')
import фід_каталог as ФК, colorspace as cs, колір_простір_риси as КР
т = collections.defaultdict(list)
for r in ФК._прочитати_каталог('каталог_повний.xml', 0)['каталог']:
    if r.get("lab") and cs.lch(tuple(r["lab"]))[1] > 8: т[r.get("колір_назва")].append(cs.lch(tuple(r["lab"]))[2])
мед = lambda *сл: math.degrees(math.atan2(sum(math.sin(math.radians(h)) for с in сл for h in т[с]),
                                          sum(math.cos(math.radians(h)) for с in сл for h in т[с]))) % 360
кут = lambda a, b: abs((a - b + 180) % 360 - 180)
ВЗ = [мед("оливковий"), мед("блакитний"), мед("бордовий")]
КОМП = [(("бордовий", "бордо", "бургунді"), ("темно-зелений", "хвойний", "смарагдовий")),
        (("кемел",), ("темно-синій",)), (("бірюзовий", "петроль"), ("теракотовий", "рудий"))]
СЛОВА = dict(червоний=0, помаранчевий=60, коричневий=60, жовтий=120, зелений=180, блакитний=240, синій=240, фіолетовий=300)
ПІСЛЯ = КР._КОЛО
ДО = ((25.0, 0.0), (54.0, 45.0), (69.0, 90.0), (157.0, 180.0), (188.0, 225.0), (282.0, 270.0))
for хто, коло in (("ДО", ДО), ("ПІСЛЯ", ПІСЛЯ)):
    КР._КОЛО = коло
    відх = []
    for i, h in enumerate(ВЗ):
        ц, ін = [cs.зсув_на_колі(h, 120), cs.зсув_на_колі(h, 240)], [x for j, x in enumerate(ВЗ) if j != i]
        відх.append(min(max(кут(ц[0], ін[0]), кут(ц[1], ін[1])), max(кут(ц[0], ін[1]), кут(ц[1], ін[0]))))
    комп = [кут(cs.доповнення(мед(*а)), мед(*б)) for а, б in КОМП]
    сл = {с: round((cs.у_коло_художника(мед(с)) - м + 180) % 360 - 180) for с, м in СЛОВА.items()}
    лупа = max(cs.у_коло_художника(h + 1) - cs.у_коло_художника(h) for h in range(50, 66))
    print("%-5s лупа h50–65: %.1f° кола на 1° тону" % (хто, лупа))
    print("%-5s взірець-тріада з якорів олива/блакит/бордо: %s · суд ✔ %d з 3 · комплементи %s · слова %s"
          % (хто, "/".join("%.1f°" % x for x in відх), sum(x <= 25 for x in відх), "/".join("%.1f°" % x for x in комп), сл))
    print("ФАКТ · %s: тріада взірця впізнана з %d із 3 якорів, найбільший відхил %.1f°, комплемент найгірший %.1f°"
          % (хто, sum(x <= 25 for x in відх), max(відх), max(комп)))
