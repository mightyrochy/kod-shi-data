# -*- coding: utf-8 -*-
"""Рядок 212 / доповнення менеджера 28.09: чи доїжджає ВНУТРІШНІЙ КОД латиницею у
видимий текст жінки.

Читає вивантаження стенда (`ZNIMKY=<тека>`: `картки.txt` і `текст_екранів.txt`) і шукає в
них токени, які Є кодами внутрішньої мови — дрес-коди, слоти, типи, кольори, схеми, нагоди,
місця (`внутрішня_мова.ТАБЛИЦЯ` + `формальність.КОДИ_ДІАПАЗОНИ`). Назви крамниць і брендів
латиницею («GARDA», «CAPRI») кодами не є і не рахуються — саме тому звірка йде за СЛОВНИКОМ
кодів, а не за «будь-яка латинка», і регістр значущий («Other» у назві речі — бренд, не код
`other`). Слова САМОЇ ЖІНКИ рахуються теж: проба їх не відрізняє, тому кожне входження
друкується з файлом і рядком — щоб людина побачила, чиє це слово.
Запуск із теки `джерела`: `python3 проби/ч9_коди_на_екрані.py <тека знімків> [ще тека…]`"""
import os, re, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ)
os.chdir(ТУТ)
import внутрішня_мова as ВМ, формальність as ФО
КОДИ = set()
for _гр, _зн in (ВМ.ТАБЛИЦЯ or {}).items():
    КОДИ |= {str(к) for к in (_зн or {})}
КОДИ |= {str(к) for к in (ФО.КОДИ_ДІАПАЗОНИ or {})}
КОДИ = {к for к in КОДИ if re.fullmatch(r"[a-z][a-z0-9_]{2,}", к)}
СЛОВО = re.compile(r"[A-Za-z][A-Za-z0-9_]*")
for тека in (sys.argv[1:] or ["."]):
    знайдено, рядків = {}, 0
    for ім in ("картки.txt", "текст_екранів.txt"):
        ш = os.path.join(тека, ім)
        if not os.path.exists(ш):
            continue
        for н, рядок in enumerate(open(ш, encoding="utf-8"), 1):
            рядків += 1
            for т in СЛОВО.findall(рядок):
                if т in КОДИ:
                    знайдено.setdefault(т, []).append("%s:%d" % (ім, н))
    print("%s · рядків видимого тексту %d · КОДІВ У ВИДИМОМУ ТЕКСТІ: %d"
          % (os.path.basename(тека.rstrip("/")) or тека, рядків, sum(len(v) for v in знайдено.values())))
    for т, де in sorted(знайдено.items()):
        print("   «%s» ×%d  →  %s" % (т, len(де), ", ".join(де[:3])))
print("словник кодів, за яким шукали: %d" % len(КОДИ))
