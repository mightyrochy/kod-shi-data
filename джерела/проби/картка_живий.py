"""Вимір суду на записах шести сцен чату: ті самі відповіді, без моделі й мережі."""
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'прилади'))
from replay_картки_живий import виміряти


def main():
    """Надрукувати хибні відмови й збереження справжніх відмов на живих записах."""
    л = виміряти()['лічба']
    print(json.dumps(л, ensure_ascii=False))
    assert (л['сцен'], л['записів']) == (6, 16)
    assert л['хибних_відмов'] == л['хибних_сцен'] == л['повторних_обовʼязкових_питань'] == 0, л
    assert л['прийнято_чужих'] == 0
    assert л['контролів_відкинуто'] == л['контролів'] == 5
    assert л['доданих_фактів_відкинуто'] == 2
    assert л['часткова_мітка_відкинута'] == 1


if __name__ == '__main__':
    main()
