const fs = require('fs'), vm = require('vm'), assert = require('assert');
const поточний = fs.readFileSync('показ.html', 'utf8');
const старий = fs.readFileSync(process.argv[2], 'utf8');
function функція(т, ім){
  const м = new RegExp('(?:async )?function ' + ім + '\\(').exec(т);
  return м ? т.slice(м.index, т.indexOf('\n}', м.index) + 2) : '';
}
(async ()=>{
  for (const [ім, т] of [['ДО', старий], ['ПІСЛЯ', поточний]]){
    const ід = 'ф2·2', новий = {дані: 'her-touch'}, рамка = {ліво: 200, верх: 300, право: 400, низ: 500};
    const річ = {ід, фото: 'ф1', рамка, дотик: true, назва: 'skirt'};
    const п = {речі: [{ід, фото: 'ф2', назва: 'skirt'}], лічильник: 0, номер: 0, показано_о: Date.now(),
      звіт: {дії: []}, hex: {}, мініатюри: {}, назви: {}, контекст: {база: {}, пікселі: {[ід]: {}}, пікселі_фото: {[ід]: {ф1: {}, ф3: {}}}}};
    let в = {речі: [річ], дії: [{op: 'set', ід, поле: 'фото', було: 'ф2', стало: 'ф1'}]};
    const с = vm.createContext({ОЦ: {перелік: п, етапи: {}, фото: [{ід: 'ф1'}]}, Date, Set,
      містП: async (_т, д)=>д.крок === 'виправити' ? в : {}, кадрРечіУрлП: async ()=>'thumb', малюватиПерелікП(){}});
    for (const ф of ['записатиПікселіРечіП', 'застосуватиВиправленняП', 'виміриВПерелікуП']) vm.runInContext(функція(т, ф), с);
    с.п = п; с.кадр = новий;
    await vm.runInContext('застосуватиВиправленняП(п, [], "touch", {"ф2·2": кадр})', с);
    const к = п.контекст, той = к.пікселі[ід] === к.пікселі_фото[ід].ф1 && Object.keys(к.пікселі_фото[ід]).length === 1;
    console.log(ім, 'один кадр:', той, 'фото:', Object.keys(к.пікселі_фото[ід]), 'дія:', п.звіт.дії[0].ід);
    if (ім === 'ПІСЛЯ'){
      assert(той); assert.strictEqual(к.пікселі[ід], новий); assert.strictEqual(п.звіт.дії[0].ід, ід);
      п.речі[0] = {...річ, фото: 'ф2'}; к.пікселі_фото[ід] = {ф1: новий}; с.суд = {речі: [річ]};
      await vm.runInContext('виміриВПерелікуП(суд)', с);
      assert.strictEqual(п.речі[0].фото, 'ф1'); assert.strictEqual(к.пікселі[ід], к.пікселі_фото[ід].ф1);
      в = {речі: [], дії: [{op: 'remove', ід, поле: 'річ'}]};
      await vm.runInContext('застосуватиВиправленняП(п, [], "touch")', с);
      assert(!(ід in к.пікселі) && !(ід in к.пікселі_фото));
    }
  }
})().catch(e=>{ console.error(e); process.exitCode = 1; });
