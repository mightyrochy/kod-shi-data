# -*- coding: utf-8 -*-
"""Рядок 46: образ без ОСНОВИ (сукня чи верх+низ) — це аксесуари, і самими
аксесуарами на картку він не йде НІКОЛИ. ДО ПРАВКИ «нема_верху_низу» не входив
у СЛОТИ_БЛОКЕРА — найповніший із неповних (самі аксесуари) їхав на картку з
чесним рядком. ПІСЛЯ — основа в тих самих сходах ремонту, що сумка й взуття."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import pipeline as PL

СЦ = {"нагода": "побачення"}
річ = lambda і, с, н: dict(id=і, слот=с, назва=н, тип=н)
АКСЕСУАРИ = {"сережки": річ("e1", "сережки", "Сережки Malachite"),
             "взуття": річ("s1", "взуття", "Човники"), "сумка": річ("b1", "сумка", "Клатч"),
             "прикраси": річ("e2", "прикраси", "Прикраса Аврора"),
             "верхній_шар": річ("j1", "верхній_шар", "Піджак")}
ІД_АКСЕСУАРІВ = [р["id"] for р in АКСЕСУАРИ.values()]


def вердикт():
    речі = [dict(р) for р in АКСЕСУАРИ.values()]
    бл = PL.блокери_структури(PL.структура_образу(речі, None, СЦ), речі)
    return {"образи": [{"ід": "о1", "речі": list(ІД_АКСЕСУАРІВ),
                        "структура": {"ок": not бл, "блокери": бл}}]}


for назва, пул_основи in (
        ("а) у пулі є сукня", {"сукня": [річ("d1", "сукня", "Сукня міді")]}),
        ("б) сукні нема, є верх+низ",
         {"верх": [річ("t1", "верх", "Блуза")], "низ": [річ("n1", "низ", "Спідниця")]}),
        ("в) пулу основи нема зовсім", {})):
    пул = {сл: [р] for сл, р in АКСЕСУАРИ.items()}
    пул.update(пул_основи)
    п = PL.повнота_набору(вердикт(), кандидати=пул, сценарій=СЦ, дібрати=True)
    на_картці = п["ід"]
    print("%-30s на картку %s · додав_код %s · рядок: %s"
          % (назва, на_картці or "— (картки нема)",
             [d["слот"] for d in п["дібрані"]] or "—",
             (п["рядок"] or "нічого зайвого")[:70]))
    assert sorted(на_картці) != sorted(ІД_АКСЕСУАРІВ), "самі аксесуари без основи на картці"
