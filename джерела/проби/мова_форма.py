"""Рядки 3450, 3381, 3452: replay записаних ходів розмови й перекладів картки (ЖИВІ-13 А, ЖИВІ-12 Б і А) тим самим
кодом (`прийняти_розмову` → `суд_частин`). Друкує частку ходів, де в показаній бульбашці є тема чи обіцянка повз
`invite_topics` (наказ «Розкажи/Опиши» чи «запропоную/підберу/буде» в `text`), і частку з «ви» — у бульбашці й у
перекладах картки. Слова тут читає ПРОБА (мірило очима), не код. Новий формат `text` [{about, says}] записів ще не має:
ПІСЛЯ — механізм на тих самих реченнях. Запуск: cd джерела && python3 проби/мова_форма.py"""
import json, re, subprocess, sys
sys.path.insert(0, "."); import мовний_шар as М
ГІЛКИ = {"origin/claude/zhyvi-13": "аудит/живі_13/А", "HEAD": "аудит/живі_12"}
ВИ = re.compile(r"(?i)\b(ви|вас|вам|ваш\w*|\w+(?:ете|єте|іть|йте))\b")
ПОЗА = re.compile(r"(?i)\b(розкажи|опиши|поділись|запропоную|підберу|можу запропонувати|образ буде|буде ідеальним|"
                  r"обиратимемо|зробимо|одягай|одягайтеся)\b")
def файли(г, т):
    return [ф for ф in subprocess.run(["git", "-c", "core.quotepath=false", "ls-tree", "-r", "--name-only", г, "../" + т],
            capture_output=True, text=True).stdout.split() if "мовний_шар" in ф]
def відповідь(г, ф):
    т = subprocess.run(["git", "show", "%s:%s" % (г, ф)], capture_output=True, text=True).stdout
    return т.split("── ВІДПОВІДЬ", 1)[1].split("──", 1)[1] if "── ВІДПОВІДЬ" in т else ""
ходи, картки = [], []
for г, т in ГІЛКИ.items():
    for ф in файли(г, т):
        (ходи if "хід_розмови" in ф else картки).append((ф.split("/")[-3], відповідь(г, ф)))
поза = ви = 0
for сц, в in ходи:
    р = М.прийняти_розмову(в); ч = р["частини"]
    б = М.суд_частин(ч, ч.get("invite_topics") or [], [], записано=р["внутрішня"])[0]
    поза += bool(ПОЗА.search(р.get("текст") or "")); ви += bool(ВИ.search(б))
print("ходів розмови:", len(ходи), "| тема чи обіцянка в text повз суд:", поза, "| «ви» в бульбашці:", ви)
об = [М._обʼєкт(в)[0] for _, в in картки]; об = [x for x in об if isinstance(x, dict)]
кв = sum(bool(ВИ.search(" ".join(str(x) for x in о.values()))) for о in об)
print("перекладів картки (JSON):", len(об), "| з «ви»:", кв)
# ПІСЛЯ, механізм: ті самі речення в новому форматі — речення з кодом поза `update` жінка не читає
в = {"update": {"occasion": {"quote": "на роботу", "value": "work"}}, "need": "none", "invite_topics": ["jewelry"],
     "text": [{"about": ["occasion"], "says": "Записала, що йдеш на роботу."},
              {"about": ["register"], "says": "Розкажи про стиль, який тобі подобається."},
              {"about": ["jewelry", "register"], "says": "Я запропоную тобі прикраси та стиль для цього образу."}],
     "invite": "Які прикраси ти хочеш до цього образу — можна й пропустити."}
р = М.прийняти_розмову(json.dumps(в, ensure_ascii=False))
б, _, відк, *_ = М.суд_частин(р["частини"], ["jewelry", "register"], [], записано=р["внутрішня"])
print("ПІСЛЯ (механізм):", б, "| відкинуто:", [(x["чому"], x.get("чуже")) for x in відк])
