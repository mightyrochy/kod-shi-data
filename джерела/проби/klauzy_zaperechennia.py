# -*- coding: utf-8 -*-
"""Чи стосується заперечення лише СВОЄЇ частини речення.

Знахідка тестувальниці: кома й «і» клаузою не були, тож «хочу смужку і НЕ ХОЧУ
підборів» давало межу на смужку — заперечення чужої речі підтверджувало вето.
Друкує клаузи й вето на шести фразах (три хибні, три-запобіжники) і число
смугастих речей у пулі. Із теки `джерела`: PYTHONPATH=. python3 проби/klauzy_zaperechennia.py"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, feed as Ф, паспорт_нагоди as ПН

ВЕТО = dict(принти=["смужка"], типи=["підбори"], тканини=["шкіра", "замша"])
ФРАЗИ = ("хочу смужку і не хочу підборів", "люблю смугасте, не ношу клітинку",
         "хочу смугасту сорочку і не хочу підборів", "ні смужки, ні клітинки",
         "не хочу ні підборів, ні смужки", "смугастий одяг мені не йде",
         "не ношу шкіру і замшу", "не ношу шкіру, а також замшу")
ВХ = json.load(open("стенд_вх.json", encoding="utf-8"))
ВХ["каталог"] = Ф.каталог_на_диску("каталог_brief.xml")


def смугастих(слова):
    """Скільки смугастих речей лишилось у кандидатах при цих словах жінки."""
    п = dict(вето=dict(ВЕТО), слова=слова)
    r = json.loads(B.виклик("запити", json.dumps(dict(ВХ, паспорт=п), ensure_ascii=False)))
    р = [x for с in r["кандидати"].values() for x in с]
    return sum(1 for x in р if re.search(r"полос|смуг|смуж", str(x.get("назва") or ""), re.I)), len(р)


for ф in ФРАЗИ:
    в = ПН.вето_тверде(dict(вето=dict(ВЕТО), слова=ф))
    print("«%s»\n   клаузи %s\n   вето: принти %s · типи %s · тканини %s"
          % (ф, ПН.клаузи_заперечення(ф), в["принти"], в["типи"], в["тканини"]))
# ЇЇ ПРОХАННЯ НЕ СТАЄ МЕЖЕЮ ЧЕРЕЗ СУСІДНЮ ВІДМОВУ…
assert not ПН.вето_тверде(dict(вето=dict(ВЕТО), слова=ФРАЗИ[0]))["принти"]
assert not ПН.вето_тверде(dict(вето=dict(ВЕТО), слова=ФРАЗИ[2]))["принти"]
# …а однорідні додатки одного заперечення не губляться
assert ПН.вето_тверде(dict(вето=dict(ВЕТО), слова=ФРАЗИ[6]))["тканини"] == ["шкіра", "замша"]
assert ПН.вето_тверде(dict(вето=dict(ВЕТО), слова=ФРАЗИ[4]))["принти"] == ["смужка"]
for ф in ("хочу смугасту сорочку і не хочу підборів", "не хочу ні підборів, ні смужки"):
    print("каталог · «%s» → смугастих %d із %d" % (ф, *смугастих(ф)))
