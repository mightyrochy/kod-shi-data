# -*- coding: utf-8 -*-
"""Чи стосується заперечення лише СВОЄЇ частини речення (принти | типи | тканини).
Знахідка тестувальниці: кома й «і» клаузою не були — «хочу смужку і НЕ ХОЧУ підборів» давало межу на
смужку. Повернення тестувальниці №2: просте «ні» заперечувало всю клаузу — «смужку ТАК, клітинку ні»
давало межу й на смужку. Із теки `джерела`: PYTHONPATH=. python3 проби/klauzy_zaperechennia.py"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, feed as Ф, паспорт_нагоди as ПН
ВЕТО = dict(принти=["смужка", "клітинка"], типи=["підбори"], тканини=["шкіра", "замша"])
С, К, П, Ш, З = "смужка", "клітинка", "підбори", "шкіра", "замша"
ОЧІКУВАНЕ = {                                      # фраза → чого вона СПРАВДІ не хоче
    "хочу смужку і не хочу підборів": ([], [П], []), "ні, смужку хочу": ([], [], []),  # вступне «ні» — не межа
    "люблю смугасте, не ношу клітинку": ([К], [], []), "смугастий одяг мені не йде": ([С], [], []),
    "хочу смугасту сорочку і не хочу підборів": ([], [П], []), "ні смужки, ні клітинки": ([С, К], [], []),
    "не хочу ні підборів, ні смужки": ([С], [П], []), "не ношу шкіру і замшу": ([], [], [Ш, З]),
    "не ношу шкіру, а також замшу": ([], [], [Ш, З]), "смугасте — ні": ([С], [], []),
    "смужку так, клітинку ні": ([К], [], []), "клітинку ні": ([К], [], []),  # заднє «ні» — лише свій член
    # ── 25.09: три форми, яких гейт не чув (знахідка тестувальниці) ──────────
    "ніяких підборів": ([], [П], []),              # вже читалось — тримаємо пробою
    "смужку? ні": ([С], [], []),                   # питання й відповідь на нього
    "смугасте ні в якому разі": ([С], [], []),     # заднє «ні» з підсиленням
    "клітинку ні за що": ([К], [], []),
}
ВХ = dict(json.load(open("стенд_вх.json", encoding="utf-8")), каталог=Ф.каталог_на_диску("каталог_brief.xml"))


def смугастих(слова):
    """Смугастих речей і всього кандидатів у пулі при цих словах жінки."""
    r = json.loads(B.виклик("запити", json.dumps(dict(ВХ, паспорт=dict(вето=dict(ВЕТО), слова=слова)), ensure_ascii=False)))
    р = [x for с in r["кандидати"].values() for x in с]
    return sum(1 for x in р if re.search(r"полос|смуг|смуж", str(x.get("назва") or ""), re.I)), len(р)


for ф, очік in ОЧІКУВАНЕ.items():
    факт = tuple(ПН.вето_тверде(dict(вето=dict(ВЕТО), слова=ф))[k] for k in ("принти", "типи", "тканини"))
    print("%s «%s» → клаузи %s · вето %s" % ("✔" if факт == очік else "✗", ф, ПН.клаузи_заперечення(ф), факт))
    assert факт == очік, (ф, факт, очік)
for ф in ("хочу смугасту сорочку і не хочу підборів", "смужку так, клітинку ні", "ні смужки, ні клітинки"):
    print("каталог · «%s» → смугастих %d із %d" % (ф, *смугастих(ф)))
