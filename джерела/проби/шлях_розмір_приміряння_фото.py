"""Приміряння (показ.html:7151-7300) — ЄДИНИЙ виклик на gemini-3.1-flash-image,
БУДУЄТЬСЯ ЦІЛКОМ У JS (не в збирач_промптів/Python) і ЖОДНОГО разу не вимірювався
на сирих прогонах ноутбука 25.09 (у аудит/тести/сирі_2026-09-25/ képи ПРИМІРЯННЯ.txt.gz
несуть лише текст-обгортку 772-1400 симв — фото рахуються окремо і не в тому самому
вимірі симв). У цьому ж виклику: її фото на повний зріст і ЇЇ ЖЕ закріплені речі
йдуть base64 (до МАКС_СИМВОЛІВ_ФОТО симв/фото), а КАТАЛОЖНІ речі — адресою (`type:'url'`,
дешево в JSON.stringify до того, як міст їх довантажить і лише тоді зважить проти
СТЕЛЯ_ФОТО_РАЗОМ). Проба звіряє цей факт прямо в коді. Друкує факт.
Запуск: cd джерела && python3 проби/шлях_розмір_приміряння_фото.py"""
import os, re
показ = open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                          "показ.html"), encoding="utf-8").read()
worker = open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                          "worker.js"), encoding="utf-8").read()

поч = показ.index("async function приміряти(поз)")
блок = показ[поч:показ.index("async function", поч + 10)]

catalog_url = "{type:'image', source:{type:'url', url:р.фото}}" in блок
власні_base64 = "свої.map(x=>блокФотоП(x.ф))" in блок
її_base64 = "{type:'image', source:{type:'base64', media_type:її.тип, data:її.дані}}" in блок
не_міст_запити = "містП('запити'" not in блок and "містП('опис'" not in блок

print("каталожні речі йдуть URL (дешево в символах):", catalog_url)
print("її закріплені речі йдуть base64 (повна ціна в символах):", власні_base64)
print("її фото на повний зріст йде base64:", її_base64)
print("приміряння не будує промпт через Python-ендпойнти 'запити'/'опис':", не_міст_запити)
assert catalog_url and власні_base64 and її_base64 and не_міст_запити

вираз = re.search(r"СТЕЛЯ_ФОТО_РАЗОМ\s*=\s*([0-9*\s]+);", worker).group(1).strip()
байти_разом = 1
for частка in вираз.split("*"):
    байти_разом *= int(частка.strip())
print("worker.js: СТЕЛЯ_ФОТО_РАЗОМ (байти, лише URL-фото після довантаження мостом) = %d (%s)" % (байти_разом, вираз))
print("а СТЕЛЯ_ВХОДУ_СИМВ (символи, рахує base64 з клієнта одразу) — рахується РАНІШЕ, worker.js:283-285")
