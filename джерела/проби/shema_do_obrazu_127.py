# -*- coding: utf-8 -*-
"""Рядок 127: суд судить образ ТІЄЮ схемою, якою зібрано пул, і схема доїжджає до образу.
ДО — пакет без `явні` і затиск `min(номер, len-1)` (як стояло в `від_моделі`);
ПІСЛЯ — `міст_основи._пакет_гілки` (той самий вираз, що й у `запити`).
Друкує ще й голову акцентного слота: схема, яка просить колір, має ставити колір першим.
Запуск: cd джерела && python3 проби/shema_do_obrazu_127.py [каталог]"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from міст_вхід import _збірка, _якір, _нормалізувати_вхід, _застосувати_паспорт
import міст_основи as МО
from міст_пакет import _пакет_каталогу
from колір_річ import сім_я
from colorspace import hx
КАТ = sys.argv[1] if len(sys.argv) > 1 else "каталог_повний.xml"
ЯДРО = ("сукня", "верх", "низ", "взуття", "сумка", "комплект")
сім = lambda р: (сім_я(hx(р["hex"])) if (р or {}).get("hex") else "")
кольором = lambda ф: bool(ф) and not ф.startswith("нейтраль")
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
збої = 0
for намір in ("conventional", "statement", "comfort_first"):
    for схема, номер in (("тріада", 4), ("нейтрали+акцент", 2)):
        d = _нормалізувати_вхід(_застосувати_паспорт(
            dict(вх, каталог=КАТ, гілка=номер, схема=схема, намір=намір)))
        F, T, зріст, kw = _збірка(d)
        п, і, сх, підм = МО._пакет_гілки(d, F, T, зріст, kw, _якір(d), намір)
        # ДО: та сама розвилка без імені схеми й затиск по довжині — два колишні вирази
        рс = МО._пакет(F, T, зріст, kw, _якір(d), намір, None, None, None)["палітри"]["розвилка"]
        до = рс[min(номер, len(рс) - 1)]["схема"]
        кан = _пакет_каталогу(d, F, T, п, і)["кандидати"]
        речі = [р for с in ЯДРО for р in (кан.get(с) or [])]
        голови = {с: (сім((кан.get(с) or [{}])[0]) or "—") for с in ("взуття", "сумка")}
        збої += int(п["палітри"]["розвилка"][і]["схема"] != схема or підм is not None)
        print("%-13s пул=%-18s суд ДО=%-26s ПІСЛЯ=%-18s ядро=%3d хром=%2d голови=%s"
              % (намір, схема, до, п["палітри"]["розвилка"][і]["схема"], len(речі),
                 sum(1 for р in речі if кольором(сім(р))), голови))
print("схем розійшлось ПІСЛЯ: %d (має бути 0)" % збої)
sys.exit(1 if збої else 0)
