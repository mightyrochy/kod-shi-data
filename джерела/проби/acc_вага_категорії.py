"""Категорійна вага зберігає діагностику й обмеження конструктора."""
import pathlib
import sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from реєстр_сила import зн, неперервна_сила


def main():
    """Звірити шкалу після стель, нуль питання та несумісність режимів."""
    for правило, сила in (("K-SHO-13", "strong"), ("K-SHO-15", "soft"),
                         ("K-SHO-08", "strong"), ("K-END-02", "soft"),
                         ("K-EYE-01", "питання")):
        for вимір in (0, 0.01, 100):
            з = зн(правило, сила, "суть", [], "чому", вимір=вимір, поріг=5,
                   вага="категорія")
            assert з["сила_нп"] == неперервна_сила(з["сила"])[0], з
            assert з["поріг"]["значення"] == 5
            assert "категорія" in з["сила_нп_джерело"] or сила == "питання"
            if сила == "питання":
                assert з["сила_нп"] == 0 and not з["блокує"]
    for kw in (dict(вага="категорія", частка=0.5), dict(вага="довільна")):
        try:
            зн("K-SHO-13", "strong", "суть", [], "чому", **kw)
        except ValueError:
            pass
        else:
            raise AssertionError(kw)
    print("категорійна вага: 15 входів і 2 хибні режими — гаразд")


if __name__ == "__main__":
    main()
