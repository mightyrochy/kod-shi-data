"""ПРОХАННЯ СТАЛО ВЕТО (рядок 156). «Можна яскравий верх — куртку чи жакет, не темного кольору» (Ір) →
модель поклала `вето.типи=["блейзер","куртка"]`, і код тримав це межею двома каналами (бриф «Не хоче: …»
і `жорстке_ні`); дзеркальне, з боку коду: «не ношу куртки, краще пальто чи тренч» забороняло й пальто з
тренчем. 20 речень пʼяти видів: скільки типів код тримає межею ХИБНО і скільки СПРАВЖНІХ меж губиться,
ДО і ПІСЛЯ, обома каналами. Пул міряє `veto_pul_156.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B, pipeline as PL
# (слова жінки, що модель поклала у вето.типи, типи, які СПРАВДІ тверді)
ВИПАДКИ = [("Можна яскравий верх — куртку чи жакет, не темного кольору", ["блейзер", "куртка"], []),
    ("Хочу куртку", ["куртка"], []), ("Можна шопер", ["шопер"], []), ("Давай сукню", ["сукня"], []),
    ("Куртку, але не темного", ["куртка"], []), ("Сукню, не чорну", ["сукня"], []),
    ("Не ношу блейзери", ["блейзер"], ["блейзер"]), ("Не ношу кросівки", ["кросівки"], ["кросівки"]),
    ("Не ношу міні. Хочу сукню", ["сукня"], []),
    # КЛАУЗА, А НЕ РЕЧЕННЯ: відмова кінчається на протиставленні й на новій клаузі бажання
    ("Не ношу куртки, краще пальто чи тренч", ["куртка", "пальто", "тренч"], ["куртка"]),   # контроль куратора
    ("Без підборів, але можна платформу", ["підбори", "платформа"], ["підбори"]),
    ("Не люблю сукні, хочу штани", ["сукня", "штани"], ["сукня"]),
    ("Не ношу шкіру, а також замшу", ["шкіра", "замша"], ["шкіра", "замша"]),   # продовження, не контраст
    ("Не хочу светр, натомість жакет", ["светр", "блейзер"], ["светр"]),
    # СЛОВНИК ВІДМОВ — звичайні українські; останні три БАГАТОСЛІВНІ (звіряються послівно)
    ("Спідниці мені не йдуть", ["спідниця"], ["спідниця"]), ("Ненавиджу клатчі", ["клатч"], ["клатч"]),
    ("Мені не подобаються ботфорти", ["ботфорти"], ["ботфорти"]),   # множина: «не подобаються»
    ("Не ношу топи на бретелях", ["топ на бретелях"], ["топ на бретелях"]),   # багатослівне
    ("Не ношу шкіряних штанів, краще джинси", ["шкіряні штани", "джинси"], ["шкіряні штани"]),
    ("Терпіти не можу синтетику, краще бавовна", ["синтетика", "бавовна"], ["синтетика"])]
хиб, проп, бриф = [0, 0], [0, 0], [0, 0]
for слова, мод, тверді in ВИПАДКИ:
    п = dict(слова=слова, вето=dict(типи=list(мод), тканини=[], принти=[], кольори=[], зони=[]))
    р, треба = (B._застосувати_паспорт(dict(паспорт=п, сценарій={})),
                {w for т in тверді for w in PL.слова_вето(т)})
    for i, ж in enumerate([{w for т in мод for w in PL.слова_вето(т)}, set(р["жорстке_ні"] or [])]):
        хиб[i] += len(ж - треба); проп[i] += len(треба - ж)          # ДО (старе правило) / ПІСЛЯ
        if i and (ж - треба or треба - ж): print("   ✗ «%s» → зайве %s · бракує %s"
                                                 % (слова[:42], sorted(ж - треба), sorted(треба - ж)))
    рядок = next((x for x in р["вимоги"].split("\n") if x.startswith("Не хоче:")), "")
    чуже = [т for т in мод if т not in тверді]      # лишити в брифі, прибравши з пулу, = не прибрати
    бриф[0] += len(чуже); бриф[1] += len([т for т in чуже if т in рядок])   # другий канал тієї ж межі
print("речень %d · хибних твердих меж: ДО %d → ПІСЛЯ %d · пропущених справжніх: ДО %d → ПІСЛЯ %d"
      "\n   той самий гейт у брифі моделі («Не хоче: …»): ДО %d → ПІСЛЯ %d"
      % (len(ВИПАДКИ), хиб[0], хиб[1], проп[0], проп[1], бриф[0], бриф[1]))
assert (хиб[1], проп[1], бриф[1]) == (0, 0, 0), "хибні, пропущені межі або хибне «Не хоче» лишились"
