# -*- coding: utf-8 -*-
"""ПРОХАННЯ СТАЛО ВЕТО (рядок 156). Тестувальниця «Ір»: «Можна яскравий верх —
куртку чи жакет, не темного кольору». Модель поклала в паспорт
`вето.типи = ["блейзер", "куртка"]`, і код прийняв це ДВОМА каналами — брифом
«Не хоче: …» і `жорстке_ні` (фільтр `composer._придатні`): з образу зникло саме
те, чого вона просила. Проба міряє на 21 реченні трьох видів (прохання, відмова,
«X, але не такого кольору»), скільки типів код тримає межею ХИБНО і скільки
СПРАВЖНІХ меж губиться — ДО і ПІСЛЯ, на обох каналах. Запуск: cd джерела &&
python3 проби/veto_prokhannia_156.py"""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B, pipeline as PL
# (слова жінки, що модель поклала у вето.типи, типи, які СПРАВДІ тверді)
ВИПАДКИ = [("Можна яскравий верх — куртку чи жакет, не темного кольору", ["блейзер", "куртка"], []),
    ("Хочу куртку", ["куртка"], []), ("Хочу блейзер до цього", ["блейзер"], []), ("Можна шопер", ["шопер"], []),
    ("Можна кросівки", ["кросівки"], []), ("Хочеться светр", ["светр"], []), ("Давай сукню", ["сукня"], []),
    ("Хочу чоботи на низькому ходу", ["чоботи"], []), ("Не ношу човники", ["човники"], ["човники"]),
    ("Не ношу блейзери взагалі", ["блейзер"], ["блейзер"]), ("Не ношу кросівки", ["кросівки"], ["кросівки"]),
    ("Ніколи не ношу ботфорти", ["ботфорти"], ["ботфорти"]), ("Не ношу міні. Хочу сукню", ["сукня"], []),
    ("Я не ношу клатч, незручно", ["клатч"], ["клатч"]), ("Не ношу рюкзак на подію", ["рюкзак"], ["рюкзак"]),
    ("Куртку, але не темного кольору", ["куртка"], []), ("Жакет, не сірий", ["блейзер"], []),
    ("Светр, тільки не бежевий", ["светр"], []), ("Сукню, не чорну", ["сукня"], []),
    ("Черевики, але не коричневі", ["черевики"], []), ("Кеди, не білі", ["кеди"], [])]
хиб, проп, бриф = [0, 0], [0, 0], [0, 0]
for слова, мод, тверді in ВИПАДКИ:
    п = dict(слова=слова, вето=dict(типи=list(мод), тканини=[], принти=[], кольори=[], зони=[]))
    р = B._застосувати_паспорт(dict(паспорт=п, сценарій={}))
    треба = {w for т in тверді for w in PL.слова_вето(т)}
    for i, ж in enumerate([{w for т in мод for w in PL.слова_вето(т)}, set(р["жорстке_ні"] or [])]):
        хиб[i] += len(ж - треба); проп[i] += len(треба - ж)          # ДО (старе правило) / ПІСЛЯ
        if i and (ж - треба or треба - ж): print("   ✗ «%s» → зайве %s · бракує %s"
                                                 % (слова[:42], sorted(ж - треба), sorted(треба - ж)))
    # ДРУГИЙ КАНАЛ: лишити в брифі «Не хоче: куртка», прибравши з пулу, — це не прибрати
    рядок = next((x for x in р["вимоги"].split("\n") if x.startswith("Не хоче:")), "")
    чуже = [т for т in мод if т not in тверді]
    бриф[0] += len(чуже); бриф[1] += len([т for т in чуже if т in рядок])
print("речень %d · хибних твердих меж: ДО %d → ПІСЛЯ %d · пропущених справжніх: ДО %d → ПІСЛЯ %d"
      % (len(ВИПАДКИ), хиб[0], хиб[1], проп[0], проп[1]))
print("   той самий гейт у брифі моделі («Не хоче: …»): ДО %d → ПІСЛЯ %d" % (бриф[0], бриф[1]))
assert (хиб[1], проп[1], бриф[1]) == (0, 0, 0), "хибні, пропущені межі або хибне «Не хоче» лишились"
