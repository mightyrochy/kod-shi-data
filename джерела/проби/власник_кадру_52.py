# -*- coding: utf-8 -*-
"""Наряд 5.2: чий кадр — ДО/ПІСЛЯ фактів власності (`каталог_власник_кадру.json.gz`) на вимірі й картці.
ДО — фактів нема (`читати_факти` → {}: як на main до 5.2); ПІСЛЯ — як у збірці. СПІЛЬНИЙ КАДР — файл, чиї
байти (sha256 маніфесту кадрів) стоять і на інших товарах фіду (дубль пропозиції — не інший товар). Друкує:
речей, чий колір міряється зі спільного кадру жнив; речей зі спільним кадром першим і будь-де в ряду картки;
речей без жодного кадру й скільки з них з причиною «лише фото інших товарів» — ДО → ПІСЛЯ.
Запуск: python3 проби/власник_кадру_52.py [id…]  (з id — друкує ряд картки ДО/ПІСЛЯ цих речей)"""
import collections, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed as Ф, фід_фото as ФФ, фід_власник_кадру as ВК
from фід_збагачення import збагачення_придатне
оф = Ф.читати_yml(Ф.каталог_на_диску("каталог_повний.xml"))[0]
зб, сп, хо, справжні = Ф.читати_збагачення(), ФФ.спільні_фото(оф), ФФ.хости_крамниць(оф), ВК.читати_факти()
жнив = {і for і, в in справжні.items() if в[3]}
спільні = {і: set(в[4]) | ({ФФ.файл_фото(зб[і]["фото"])} if і in жнив else set()) for і, в in справжні.items()
          if в[4] or і in жнив}
print("фактів %d · спільних кадрів жнив %d · речей зі спільними файлами %d" % (len(справжні), len(жнив), len(спільні)))
def прогін(факти):
    ВК.читати_факти = lambda *а, **к: факти
    с, ряди = collections.Counter(), {}
    for o in оф:
        з, сп_м, с_о = зб.get(o["id"]), сп.get(o.get("магазин")) or {}, спільні.get(o["id"]) or set()
        u = з.get("фото") if isinstance(з, dict) else None
        ряд = ряди[o["id"]] = ФФ.кадри_речі(o, сп_м, хо, u, збагачення=з)
        с["без кадрів"] += not ряд
        с["без кадрів: лише фото інших товарів"] += not ряд and ФФ.чому_без_кадру(o, сп_м) == "no_photo_other_items_only"
        с["вимір зі спільного"] += o["id"] in жнив and bool(збагачення_придатне(з) and not ВК.чужий_кадр_речі(o, u, сп_м))
        с["спільний першим"] += bool(ряд and ФФ.файл_фото(ряд[0]) in с_о)
        с["спільний у ряду"] += any(ФФ.файл_фото(x) in с_о for x in ряд)
    return с, ряди
(до, р0), (після, р1) = прогін({}), прогін(справжні)
for к in до:
    print("  %-38s ДО %5d → ПІСЛЯ %5d" % (к, до[к], після[к]))
зм = [і for і in р0 if р0[і] != р1[і]]
print("змінено рядів картки %d · перший кадр змінено %d · лишились без кадрів %d"
      % (len(зм), sum(bool(р0[і] and р1[і] and р0[і][0] != р1[і][0]) for і in зм), sum(bool(р0[і] and not р1[і]) for і in зм)))
print("без кадрів по крамницях:", collections.Counter(і.split("@")[-1] for і in зм if р0[і] and not р1[і]).most_common(8))
for і in sys.argv[1:]:
    print(і, "\n ДО", р0.get(і), "\n ПІСЛЯ", р1.get(і))
