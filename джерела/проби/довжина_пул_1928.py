# -*- coding: utf-8 -*-
"""Рядок 1928: K-OUT-02 у пулі верхнього шару на тілі 154 см при −6 / 0 / +5 °C — сила рангу
(`верхнє_довжина.ранг_пулу`) і скільки речей пулу нижче коліна: за виміром довжини виробу на її
тілі (де він є) і за словом `довжина_рівень`. Окремо — по всьому верхньому шару каталогу.
Запуск: PYTHONPATH=. python3 проби/довжина_пул_1928.py   (потрібен каталог_повний.xml)"""
import sys, json, subprocess, pathlib
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import fit as ПС, композитор_річ as КР, верхнє_довжина as ВД
Т = ПС.тіло(154, dict(плечі=90, груди=84, талія=64, стегна=88)); H = Т["висоти"]
ц, рз = КР.висота_рівня("коліно", H)
def вимір(x):                                           # поділ нижче зони коліна на її тілі
    н = КР.край_з_довжини(x, H)[0]
    return None if н is None else н < ц - рз
def рядок(к):
    в, с = [вимір(x) for x in к], [x.get("довжина_рівень") in ВД.НИЖЧЕ_КОЛІНА for x in к]
    return ("%3d речей · нижче коліна за виміром %d (з %d з виміром), за словом %d; розбіг: вимір так/слово ні %d,"
            " слово так/вимір ні %d" % (len(к), sum(1 for v in в if v), sum(1 for v in в if v is not None), sum(с),
            sum(1 for v, w in zip(в, с) if v and not w), sum(1 for v, w in zip(в, с) if v is False and w)))
if len(sys.argv) > 1:                                   # дочірній процес: один пул
    import bridge as B
    вх = dict(json.load(open(_К / "стенд_вх.json", encoding="utf-8")), каталог=str(_К / "каталог_повний.xml"),
              гілка=0, варіантів=6, зріст=154, обхвати=dict(плечі=90, груди=84, талія=64, стегна=88),
              випадок="прогулянка", сценарій=dict(нагода="прогулянка", місце="місто", година=12,
                                                  темп_c=float(sys.argv[1])))
    r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    кат = {c["id"]: c for c in B.каталог_останнього_пакета()}     # рядки каталогу: довжина виробу, слово
    print(рядок([кат.get(x["id"], x) for x in r["кандидати"].get("верхній_шар") or []])); sys.exit()
import feed, фід_каталог as ФК
кат = [x for x in ФК._прочитати_каталог(feed.каталог_на_диску(), ліміт_фото=0)["каталог"] if x.get("слот") == "верхній_шар"]
print("каталог, верхній шар:", рядок(кат))
for t in (-6, 0, 5):
    print("%+d °C сила %.2f · пул:" % (t, ВД.ранг_пулу(Т, t)), subprocess.run([sys.executable, __file__, str(t)],
          capture_output=True, text=True, cwd=str(_К)).stdout.strip().splitlines()[-1])
