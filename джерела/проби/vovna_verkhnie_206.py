# -*- coding: utf-8 -*-
"""Рядок 206: «бавовна 100%» читалась як вовна — `вовна_частка` брехала, а це вхід K-OUT-18.
ДО — реєстр із голим `вовн`, ПІСЛЯ — `(?<!ба)вовн` + погляд уперед на чуже волокно.
Запуск: cd джерела && python3 проби/vovna_verkhnie_206.py"""
import collections, os, re, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_верхнє as ФВ, фід_слот as ФС
ГОЛИЙ = re.compile(r"(?:вовн|шерст|wool)\w*\s*[:\-–]?\s*(\d{1,3})\s*%|(\d{1,3})\s*%\s*(?:вовн|шерст|wool)")
оф = feed.читати_yml(feed.каталог_на_диску())[0]
текст = lambda o: " ".join([str(o.get("назва") or ""), str(o.get("категорія") or ""),
                            str(o.get("опис") or ""),
                            " ".join(str(v) for v in (o.get("параметри") or {}).values())]).lower()
до = після = бавовна = злиплі = інше = 0
частки, зняті = collections.Counter(), []
for o in оф:
    т = текст(o); a, b = ГОЛИЙ.search(т), ФВ._ПРО_ВОВНУ.search(т)
    до += bool(a); після += bool(b)
    if a and b and float(a.group(1) or a.group(2)) != float(b.group(1) or b.group(2)): інше += 1
    if not a or b: continue
    ч = float(a.group(1) or a.group(2)) / 100.0
    частки[ч] += 1
    це_бавовна = т[max(0, a.start() - 2):a.start()].endswith("ба")
    бавовна += це_бавовна; злиплі += not це_бавовна
    if len(зняті) < 4:
        зняті.append((o["id"], (ФС.назва_для_людини(o) or "")[:34], ч, т[max(0, a.start() - 16):a.end() + 8].strip()))
print("ФАКТ · оферів %d · `вовна_частка` названа: ДО %d → ПІСЛЯ %d · знято хибних %d"
      % (len(оф), до, після, до - після))
print("ФАКТ · зі знятих: «бавовна» %d · злиплий склад (число ПЕРЕД своїм волокном) %d · "
      "число змінилось на ІНШЕ: %d" % (бавовна, злиплі, інше))
print("ФАКТ · які частки знято: %s (1.0 = «цільна вовна» на джинсі)" % dict(частки.most_common(5)))
for ід, н, ч, ур in зняті:
    print("ФАКТ · %-24s «%s» · було %.2f · «%s»" % (ід[:24], н, ч, ур))
верх = [o for o in оф if ФС.слот(o) == "верхній_шар"]
з_ч = [o for o in верх if (ФВ.верхні_атрибути(o) or {}).get("вовна_частка") is not None]
print("ФАКТ · верхнього шару %d · частка названа в %d · із них ≥ 0.6 (смуга K-OUT-18): %d"
      % (len(верх), len(з_ч), sum(1 for o in з_ч if ФВ.верхні_атрибути(o)["вовна_частка"] >= 0.6)))
ціла = sum(1 for o in оф if ФВ._ПРО_ВОВНУ.search(текст(o)) and re.search(r"(?<!ба)вовн|шерст|wool", текст(o)))
print("ФАКТ · СПРАВЖНЯ ВОВНА НЕ ЗАЧЕПЛЕНА: усі %d, що лишились, мають слово вовни: %s" % (після, ціла == після))
