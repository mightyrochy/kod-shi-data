"""Скарга «Ір» (24.09): «не знаю, через які слова воно витягає одні й ті самі кеди, одну й ту саму куртку».
Для кожного слова бажання: як його читає код (слотом/типом чи словами), скільки речей каталогу підходять (клас),
скільки з них іде в пул першими, у скількох слотах, і чи перша річ та сама на сідах 3,5,7,9. Запуск: cd джерела && python3 проби/slova_bazhannia_207.py"""
import json, os, sys
Д = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, Д); os.chdir(Д)
import bridge as B, feed, пакет_моделі as PL, різноманітність_пулу as R; feed.каталог_на_диску()
json.loads(B.виклик("запити", json.dumps(json.load(open("стенд_вх.json")), ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
слоти = {c.get("слот") for c in кат if c.get("слот")}
СЛОВА = ["яскравий", "куртка", "жакет", "кеди", "кросівки", "зручне", "зручне взуття", "джинси", "світлі джинси", "шарф",
         "яскравий верх", "яскравий верх, куртку чи жакет", "оригінальний без зусиль"]
for ф in СЛОВА:
    перші, дав = [], []
    for сід in (3, 5, 7, 9):
        з = R.речі_бажання(ф, кат, {с: [] for с in слоти}, сід=сід, n=10 ** 6)
        if з:
            клас, як = len(з["речі"]), "слотом %s, тип «%s»" % ("/".join(з["слоти"]), з["тип"])
            рч = R.речі_бажання(ф, кат, {с: [] for с in слоти}, сід=сід, n=getattr(R, "на_слот", lambda: 4)())["речі"]
        else:
            клас, як = len(PL.шукати_словами(кат, ф, n=10 ** 6)), "словами (назва/тип/тканина/колір)"
            рч = PL.шукати_словами(кат, ф, n=4, **({"сід": сід} if "сід" in PL.шукати_словами.__code__.co_varnames else {}))
        перші.append(рч[0]["id"] if рч else None); дав.append(рч)
    сл = {}
    for r in дав[0]: сл[r.get("слот")] = сл.get(r.get("слот"), 0) + 1
    print("ФАКТ · «%s» → %s · клас %d речей · у пул першими %d (%s) · перша річ на 4 сідах: %d різних (%s)"
          % (ф, як, клас, len(дав[0]), ", ".join("%s %d" % кв for кв in сл.items()), len(set(перші)),
             str((дав[0] or [{}])[0].get("назва"))[:40]))
