"""Ф2 2.8-Б: чистий preflight, канони сценарію/опадів і явний бюджет, без моделей."""
import sys, json
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import bridge, сценарій as СЦ, міст_пакет as МП
стан = lambda с, **д: json.loads(bridge.виклик("стан_сценарію", dict(сценарій=с, **д)))
for с, є in [({}, False)] + [({к: з}, True) for к, з in (
        ("нагода", "робота"), ("місце", "офіс"), ("дрес_код", "casual"),
        ("ошатність", [1, 2]), ("_ошатність", [1, 2]))]:
    assert стан(с)["є_сценарій"] is є, с
    print("K-IO-01", с, є)
for т, код in ((-0.1, "сніг"), (0, "сніг"), (0.1, "дощ"), (None, "дощ")):
    assert стан({"опади": "так", "темп_c": т})["код_плитки_опадів"] == код
    assert стан({}, паспорт={"опади": "так", "темп_c": т})["код_плитки_опадів"] == код
    print("грубі опади", т, код)
for о, код in (("snow", "сніг"), ("sleet", "дощ"), ("downpour", "дощ"),
               ("possible_rain", "можливий_дощ"), ("none", "ні"), ("unknown", None)):
    assert стан({}, паспорт={"опади": о})["код_плитки_опадів"] == код
    print("код опадів", о, код)
for о in ("сніг", "ні", "можливий_дощ"):
    assert стан({"опади": о}, паспорт={"опади": "rain"}, плитки_змінено=True, опади_рукою=True)["код_плитки_опадів"] == о
for о, плитка in (("sleet", "дощ"), ("downpour", "дощ"), ("snow", "сніг")):
    с = {"нагода": "робота", "опади": плитка}
    п = {"нагода": "вечірка", "опади": о}
    assert стан(с, паспорт=п, плитки_змінено=True)["код_плитки_опадів"] == плитка
assert стан({})["застосований_бюджет"] == МП.застосований_бюджет() == 43400
assert стан({}, бюджет_токенів=25000)["застосований_бюджет"] == МП.застосований_бюджет(25000) == 25000
assert стан({}, паспорт={"опади": "rain"}, опади_рукою=True)["код_плитки_опадів"] is None
assert стан({"опади": "дощ"}, паспорт={"опади": "sleet"}, опади_рукою=True)["код_плитки_опадів"] == "дощ"
import міст_вхід as В, pipeline as П
F, T, _, _ = В._збірка(json.load(open(Path(__file__).resolve().parents[1] / "стенд_вх.json")))
for б in (None, 25000):
    пак = МП._пакет_у_бюджет(П, F, [], T, ("верх",), {}, {"нагода": "робота"}, 1, бюджет=б)
    assert пак["застосований_бюджет"] == (43400 if б is None else б)
print("ручний вибір/повтор/очищення/незмінена погода/default 43400/override 25000: PASS")
