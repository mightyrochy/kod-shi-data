# -*- coding: utf-8 -*-
"""Д-1: на якому місці в пулі стоїть річ, яку модель ОБРАЛА.

Пул їде моделі списком на слот (`пакет_моделі._річ_пулу`, номер «#група·позиція»), і
порядок не випадковий: голову тримають перші страти семплера й перша річ кожної
групи (`повтор_страти.py`). Якщо модель бере згори, звуження пулу ВГОРІ важить
більше за весь інший пул. Проба читає справжні прогони власника 25.09, знаходить у
сирій відповіді складання номери речей і друкує, на яких місцях свого слота вони
стояли. Слоти з однієї речі (закріплена річ жінки) не в лічбі — вибору там нема.
Прогін: python3 проби/повтор_позиція.py     (без моделі, читає файли вердиктів)
"""
import collections, glob, json, os, re
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ТЕКА = os.path.join(os.path.dirname(ТУТ), "аудит", "тести", "власник_2026-09-25")
місця, без_вибору = [], 0
for файл in sorted(glob.glob(os.path.join(ТЕКА, "*.json"))):
    for прогін in json.load(open(файл, encoding="utf-8"))["прогони"]:
        for в in прогін["вердикти"]:
            for виклик in ((в.get("етапи") or {}).get("виклики") or []):
                текст = (виклик.get("запит") or {}).get("текст") or ""
                if not текст.startswith("{"): continue
                пул = json.loads(текст).get("пул") or {}
                поз = {str(r.get("н")): (с, i, len(рч)) for с, рч in пул.items() for i, r in enumerate(рч)}
                обрані = [поз[н] for н in re.findall(r"#\d+·\d+", виклик.get("відповідь_сира") or "") if н in поз]
                if not обрані: continue
                без_вибору += sum(1 for _, _, L in обрані if L < 2)
                місця += [x for x in обрані if x[2] > 1]
                print("%s рука %s крок «%s»: %d номерів у відповіді, слотів пулу %d"
                      % (os.path.basename(файл)[-18:-5], в.get("рука"), виклик.get("крок"), len(обрані), len(пул)))
if not місця:
    raise SystemExit("у файлах вердиктів нема виклику складання з пулом — нема чого міряти")
n = len(місця)
print("обраних речей із слотів, де був вибір: %d (ще %d — слот з однієї речі); медіанна довжина слота %d"
      % (n, без_вибору, sorted(L for _, _, L in місця)[n // 2]))
print("   ПЕРША річ слота  %3.0f %%   (за рівного шансу %.0f %%)"
      % (100.0 * sum(1 for _, i, _ in місця if i == 0) / n, 100.0 * sum(1.0 / L for _, _, L in місця) / n))
for назва, доля in (("перша чверть", 4), ("перша третина", 3), ("перша половина", 2)):
    print("   %-16s %3.0f %%   (за рівного шансу %d %%)"
          % (назва, 100.0 * sum(1 for _, i, L in місця if i < L / доля) / n, 100 // доля))
print("слоти, з яких брали: %s" % dict(collections.Counter(с for с, _, _ in місця).most_common(8)))
