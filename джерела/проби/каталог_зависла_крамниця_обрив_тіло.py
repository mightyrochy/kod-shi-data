"""Міряє досяжність відновлення DONE з утраченим або пошкодженим тілом на старті обходу."""
import tempfile
from pathlib import Path
from каталог_зависла_крамниця_sqlite_проба import обхід, прогін


def main():
    """Відновлює лише зіпсовану крамницю, залишаючи цілу DONE-чергу без запуску."""
    помилки = []
    for випадок in ("ціле", "відсутнє", "пошкоджене"):
        with tempfile.TemporaryDirectory(prefix="обрив-тіло-") as ж:
            прогін(ж)
            файл = next((Path(ж) / "проходи/hang.com").glob("*.body"))
            if випадок == "відсутнє": файл.unlink()
            if випадок == "пошкоджене": файл.write_bytes(b"CORRUPTED")
            ч = обхід.черга(ж, "hang.com")
            с, запуски = прогін(ж)
            оч = [] if випадок == "ціле" else ["hang.com"]
            добре = запуски == оч and ч == (1, int(випадок == "ціле"))
            добре &= с["hang.com"]["готово"] == "1" and с["hang.com"]["лишилось"] == "0"
            print(f"В/{випадок}: черга={ч}, повтор={запуски}, добре={добре}")
            помилки.append(not добре)
    return int(any(помилки))


if __name__ == "__main__":
    raise SystemExit(main())
