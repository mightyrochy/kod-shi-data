"""Рядок 211: цілий костюм — у слоті «комплект» і лише там; «сукня + комплект» — подвоєння.
ДО: «МОДЕЛЬ №876 ХАКІ» (на картці «Костюм хакі») лежала у слоті ВЕРХ, бо `набір_цілий` шукала слово
в СИРІЙ назві, не в назві суду; `відсікти_пул` знімала комплект лише з «верх» і «низ», не з
«верхній_шар»; пари «сукня + комплект» суд не бачив. ПІСЛЯ: 345→401 (+56, −0), 0 чужих, блокер."""
import sys, json, pathlib, collections
_К = pathlib.Path(__file__).resolve().parent.parent; sys.path.insert(0, str(_К))
import feed as Ф, bridge as B, суд_від_моделі as СМ
кат = {r["id"]: r for r in Ф._база_прогону(Ф.каталог_на_диску("каталог_повний.xml"), 0)["каталог"]}
наб = [r for r in кат.values() if r.get("набір") is True]
print("комплектів: %d · слоти: %s · типи: %s" % (len(наб), {r["слот"] for r in наб}, dict(collections.Counter(r.get("тип") for r in наб))))
for і in ("ж-02299@stolyarchuk.com.ua", "ж-08427@sarahberlin.com", "ж-05569@feelyou.com.ua"):
    print("  %-30s слот=%-9s тип=%-20s" % (і, (кат.get(і) or {}).get("слот"), (кат.get(і) or {}).get("тип")))
_б = lambda *сл: [x for x in СМ.структура_образу(
    [dict(id="i%d" % n, слот=с, назва=с, тип=с) for n, с in enumerate(сл + ("взуття", "сумка", "сережки"))],
    None, dict(нагода="театр", темп_c=16)) if "подвоєн" in x]
ПАСП = {"нагода": "театр", "речі_з_фото": [dict(ід="її-ф1", фото="ф1", слот="низ", чия="моя",
    назва="спідниця з принтом змійки", колір="коричневий", довжина="міді", принт="принт",
    закріплена=True, вимір={"hex": "#6b5a42", "слово": "коричневий"})]}
баз = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
чуже, пулів = collections.Counter(), 0
for сід in (3, 7, 13, 17, 42):
    for гілка in (0, 1):
        B._КЕШ_ПАКЕТА.clear()
        B.виклик("запити", json.dumps(dict(баз, гілка=гілка, сід=сід, паспорт=ПАСП,
            каталог=Ф.каталог_на_диску("каталог_повний.xml"), випадок="театр, 19:00, 16 °C",
            сценарій=dict(нагода="театр", місце="театр", година=19, темп_c=16)), ensure_ascii=False))
        for пак in [p for p in B._КЕШ_ПАКЕТА.values() if p.get("кандидати")]:
            пулів += 1
            for с, речі in пак["кандидати"].items():
                чуже[с] += sum(1 for x in речі if с != "комплект"
                               and (кат.get(x.get("id")) or {}).get("набір") is True)
print("пулів «театр» з її низом: %d · комплектів у ЧУЖИХ слотах: %d %s"
      % (пулів, sum(чуже.values()), {с: n for с, n in чуже.items() if n}))
