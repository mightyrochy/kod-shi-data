assert {r["слот"] for r in наб} == {"комплект"} and len(наб) == 401 and all(  # ж-08427: сира назва — теж свідок
    (кат.get(і) or {}).get("слот") == "комплект" for і in ("ж-02299@stolyarchuk.com.ua", "ж-08427@sarahberlin.com"))
assert sum(чуже.values()) == 0, "комплект мусить стояти лише у своєму слоті: %s" % dict(чуже)
