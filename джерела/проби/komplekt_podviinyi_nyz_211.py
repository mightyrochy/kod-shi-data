# -*- coding: utf-8 -*-
"""Рядок 211: комплект стоїть лише у своєму слоті, і «сукня + комплект» — подвоєння.
ДО: `відсікти_пул` знімала комплект зі слотів «верх» і «низ», а `слоти_альт` 60 комплектів несе ще
й «верхній_шар» — 38 цілих костюмів стояли в пулі «театр» поруч із її спідницею з фото (подвійний
низ у промпті); пари «сукня + комплект» `структура_образу` не бачила. ПІСЛЯ: 0 і блокер є."""
import sys, json, pathlib, collections
_К = pathlib.Path(__file__).resolve().parent.parent; sys.path.insert(0, str(_К))
import feed as Ф, bridge as B, суд_від_моделі as СМ
шлях = Ф.каталог_на_диску("каталог_повний.xml")
кат = {r["id"]: r for r in Ф._база_прогону(шлях, 0)["каталог"]}
наб = [r for r in кат.values() if r.get("набір") is True]
print("комплектів: %d · усі у слоті «комплект»: %s · чужі слоти `слоти_альт`: %s"
      % (len(наб), {r["слот"] for r in наб} == {"комплект"},
         dict(collections.Counter(с for r in наб for с in (r.get("слоти_альт") or ())))))
ПАСП = {"нагода": "театр", "речі_з_фото": [dict(
    ід="її-ф1", фото="ф1", назва="спідниця з принтом змійки", слот="низ", колір="коричневий",
    довжина="міді", принт="принт", чия="моя", закріплена=True,
    вимір={"hex": "#6b5a42", "слово": "коричневий"})]}
баз = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
чуже, пулів = collections.Counter(), 0
for сід in (3, 7, 13, 17, 42):
    for гілка in (0, 1):
        B._КЕШ_ПАКЕТА.clear()
        B.виклик("запити", json.dumps(dict(
            баз, каталог=шлях, гілка=гілка, сід=сід, паспорт=ПАСП, випадок="театр, 19:00, 16 °C",
            сценарій=dict(нагода="театр", місце="театр", година=19, темп_c=16)), ensure_ascii=False))
        for пак in [p for p in B._КЕШ_ПАКЕТА.values() if p.get("кандидати")]:
            пулів += 1
            for с, речі in пак["кандидати"].items():
                чуже[с] += sum(1 for x in речі if с != "комплект"
                               and (кат.get(x.get("id")) or {}).get("набір") is True)
print("пулів «театр» з її низом: %d · комплектів у ЧУЖИХ слотах: %d %s"
      % (пулів, sum(чуже.values()), {с: n for с, n in чуже.items() if n}))
_б = lambda *сл: [x for x in СМ.структура_образу(
    [dict(id="i%d" % n, слот=с, назва=с, тип=с) for n, с in enumerate(сл + ("взуття", "сумка", "сережки"))],
    None, dict(нагода="театр", темп_c=16)) if "подво" in x or "разом" in x]
print("блокер «сукня + комплект»:", _б("сукня", "комплект") or "НЕМА")
assert sum(чуже.values()) == 0, "комплект мусить стояти лише у своєму слоті: %s" % dict(чуже)
assert _б("сукня", "комплект") and _б("комплект", "низ") and _б("сукня", "низ")
print("ФАКТ: комплект — лише у слоті «комплект»; сукня+комплект, комплект+низ, сукня+низ — блокери.")
