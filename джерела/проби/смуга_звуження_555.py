"""Рядок 555: вужчі допуски смуги нагоди (`композитор_придатні._поза_сценою`) — своїми кодами.
На каталог_повний для смуг 2–4…5–7: скільки речей іде геть у руці 1, скільки з них ріже лише
звуження взуття (K-SHO-03, на щабель) понад розкид K-KOH-02 (2 щаблі), і скільки геть у руці 2
з вимкненим K-KOH-02 (звуження взуття — інше правило, тож діє). Моделі не кличе.
Запуск: python3 джерела/проби/смуга_звуження_555.py"""
import os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import фід_каталог as ФК, композитор_придатні as КП, формальність as ФО, правило_руки2 as П2  # noqa: E401,E402
к = [r for r in ФК._прочитати_каталог(ФК.каталог_на_диску(), ліміт_фото=0)["каталог"] if r.get("available") is not False]
print("каталог: %d речей у наявності" % len(к))
for lo, hi in ((2, 4), (3, 5), (4, 6), (5, 7), (7, 9)):
    сц = {"ошатність": [lo, hi]}
    _, геть1, _ = КП._поза_сценою(к, сц)
    лише_взуття = sum(1 for r in геть1 if r.get("слот") == "взуття" and ФО.інтервал_типу(r.get("тип"))[0] <= hi + 2)
    with П2.вимкнено(("K-KOH-02", "K-KOH-07")):
        _, геть2, _ = КП._поза_сценою(к, сц)
    print("смуга %d–%d: рука 1 геть %3d (лише звуження взуття %2d) · рука 2 без K-KOH-02 геть %2d · різниця пулів %3d"
          % (lo, hi, len(геть1), лише_взуття, len(геть2), len(геть1) - len(геть2)))
