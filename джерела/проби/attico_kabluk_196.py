"""Рядок 196: attico пише в `каблук_см` КЛАС свого фільтра, а не висоту. Проба друкує факт:
скільки пар міняють висоту/клас, скільки пласких стають кандидатами змінної пари (рядок 181)
і що каже K-SHO-16 на пласких до і після. Запуск із `джерела`: python3 проби/attico_kabluk_196.py"""
import collections, sys; sys.path.insert(0, '.')
import feed as Ф, фід_взуття as В, accessory as АР
реч, _ = Ф.читати_yml('каталог_повний.xml')
взут = [c for c in реч if (c.get('параметри') or {}).get('слот') == 'взуття']
ПОРІГ = float(АР.C['каблук_смуга_низ'])
класи, було, стало, кандидати = collections.Counter(), collections.Counter(), collections.Counter(), collections.Counter()
for c in взут:
    п = c.get('параметри') or {}
    см_було = В._число_см(п.get('каблук_см'))
    поля = В._взуттєві_поля(dict(c, параметри=п), п.get('тип'))
    смуга = поля.get('каблук_клас')
    if смуга is None:
        continue
    м = п.get('магазин') or '?'
    класи[(м, смуга)] += 1
    було[(м, см_було)] += 1
    стало[(м, поля.get('каблук_від'), поля.get('каблук_до'))] += 1
    # кандидат змінної пари: висота, коли є, сильніша за тип (рядок 181)
    низька_було = (см_було is not None and см_було < ПОРІГ)
    низька_стало = поля.get('каблук_см') is None and В.тип_речі(dict(c, параметри=п)) in (
        'балетки', 'кеди', 'кросівки', 'лофери', 'мокасини', 'сліпони')
    кандидати[(м, низька_було, низька_стало)] += 1
print('пар, де крамниця дала КЛАС, а не висоту: %d' % sum(класи.values()))
for (м, смуга), n in класи.most_common(6):
    print('  %-14s «%s» — %d' % (м, смуга, n))
print('було (число з фіду):', dict((f'{м}:{в}', n) for (м, в), n in було.most_common(4)))
print('стало (смуга від/до):', dict((f'{м}:{а}–{б}', n) for (м, а, б), n in стало.most_common(4)))
пл = sum(n for (_, б, с), n in кандидати.items() if с and not б)
print('пласких за типом, що НЕ були кандидатами змінної пари, а тепер стають: %d' % пл)
ВАРТ = lambda **кв: [round(x.get('сила_нп', 0), 2) for x in АР.вартість_носіння(
    [dict(слот='взуття', назва='проба', **кв)], тривалість_год=7, поверхня='асфальт')]
print('K-SHO-16 на весіллі 7 год по асфальту, ДО (число з фіду) → ПІСЛЯ (нижній край смуги):')
for смуга, см_було, від, до in (('до 4 см (або без підборів)', 4.0, None, 4.0),
                                ('від 4 до 6 см', 6.0, 4.0, 6.0),
                                ('більше 6 см', 6.0, 6.0, None)):
    print('  «%-26s» %s → %s' % (смуга, ВАРТ(каблук_см=см_було) or 'без вартості',
                                 ВАРТ(каблук_від=від, каблук_до=до, каблук_клас=смуга) or 'без вартості'))
