"""Межі кольору в золотій прикрасі, виразності й тональній колоні."""
import sys
sys.path.insert(0, ".")
import композитор_річ as Р, композитор_слоти as С, композитор_полюси as П


def головна():
    """Визначити лише те, що гарантовано для всього інтервалу."""
    р = dict(id="золото", слот="намисто", тип="намисто", метал="золото", lab=None,
             колір_тип="інтервал", _вікно=dict(менш_ходове=True),
             колір_не_вимір=dict(свідок="shop_word", вікно=(60, 62, 30, 40, (80, 90))))
    нота = С._нота_рідшого_металу([р], None)
    print("Золото:", bool(нота), "гарантована виразність:", Р.виразність(р))
    assert нота and Р.виразність(р) == .5
    assert С._нота_рідшого_металу([р], "золото") is None
    # Срібло рідшого ходу (під теплою палітрою) — своя нота; бажання срібла її глушить (14414).
    ср = dict(р, id="срібло", метал="срібло")
    коди = [з["code"] for з in С._нота_рідшого_металу([ср], None)]
    assert коди == ["jewellery_silver_less_usual_for_warm"], коди
    assert С._нота_рідшого_металу([ср], "срібло") is None
    for тип, вікно, є in (("інтервал", (60, 62, 30, 40, (80, 90)), True),
                           ("інтервал", (0, 100, 0, 100, None), False),
                           ("невідомо", (60, 62, 30, 40, (80, 90)), False)):
        з = dict(р, колір_тип=тип, колір_не_вимір=dict(свідок="shop_word", вікно=вікно))
        пул = {с: [dict(з, слот=с)] for с in ("верх", "низ")}
        колона = П.полюси_пулу(пул)["тональна колона"]["є"]
        print(тип, "L:", вікно[:2], "колона:", колона)
        assert колона == є
    нев = dict(р, колір_тип="невідомо")
    # Метал — код матеріалу, а не колір (крок 30 кореня Річ-колір-межі): нота рідшого ходу від роду кольору не
    # залежить, виразність невідомого кольору — 0.
    assert С._нота_рідшого_металу([нев], None) and Р.виразність(нев) == 0


if __name__ == "__main__":
    головна()
