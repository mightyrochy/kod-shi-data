# -*- coding: utf-8 -*-
"""Проба згортання дошки (ПР-1): два «PR» з новими рядками й закриттями в тому самому діапазоні згортаються
без конфлікту, а помилки падають з назвою файлу. Тека-пісочниця в tmp; друкує факт.
Запуск: python3 джерела/проби/дошка_згортання_проба.py"""
import os, shutil, subprocess, sys, tempfile
ТУТ = os.path.dirname(os.path.abspath(__file__))
ПРИЛАД = os.path.join(os.path.dirname(ТУТ), 'прилади', 'згорнути_дошку.py')
Р = lambda н, с='**ВІДКРИТО**': f'| {н} | джерело {н} | низька | {с} · текст | доказ | файли | команда |'
ДОШКА = '# шапка\n\n' + '\n'.join([Р(1), Р(2), Р(3, '**ЗАКРИТО #7**')]) + '\n'
def пробіг(файли):
    з = tempfile.mkdtemp()
    for ш, т in [('аудит/БЕКЛОГ.md', ДОШКА)] + [('аудит/дошка/' + і, т) for і, т in файли.items()]:
        os.makedirs(os.path.dirname(os.path.join(з, ш)), exist_ok=True)
        open(os.path.join(з, ш), 'w', encoding='utf-8').write(т)
    os.makedirs(os.path.join(з, 'джерела/прилади'))
    шлях = os.path.join(з, 'джерела/прилади/згорнути_дошку.py'); shutil.copy(ПРИЛАД, шлях)
    п = subprocess.run([sys.executable, шлях], capture_output=True, text=True)
    д = open(os.path.join(з, 'аудит/БЕКЛОГ.md'), encoding='utf-8').read()
    ост = sorted(os.listdir(os.path.join(з, 'аудит/дошка'))) if os.path.isdir(os.path.join(з, 'аудит/дошка')) else []
    shutil.rmtree(з); return п.returncode, п.stderr.strip(), д, ост
А = Р(10) + '\nстан 1: **ЗАКРИТО #101** · а\n' + Р(11) + '\n'
Б = Р(12) + '\nстан 1: **ЧАСТКОВО #102** · б\nстан 2: **ЗАКРИТО #102** · б\n'
рк, _, д, ост = пробіг({'а.md': А, 'б.md': Б})
ручна = '# шапка\n\n' + '\n'.join([Р(1, '**ЗАКРИТО #101**').replace('текст', 'а'), Р(2, '**ЗАКРИТО #102**').replace('текст', 'б'),
                                   Р(10), Р(11), Р(12), Р(3, '**ЗАКРИТО #7**')]) + '\n'
print('два PR, один діапазон: rc', рк, '· збігається з ручними правками:', д == ручна, '· файлів лишилось', len(ост))
рк, е, д, ост = пробіг({'а.md': А, 'в.md': Р(10, '**ВІДКРИТО** · інший') + '\n'})
print('зайнятий номер: rc', рк, '· назва файлу в помилці:', 'в.md' in е and 'а.md' in е, '· дошка не змінена:', д == ДОШКА, '· файли лишились:', ост)
рк, е, д, ост = пробіг({'г.md': 'стан 99: **ЗАКРИТО #5** · нема такого\n', 'а.md': А})
print('закриття рядка, якого нема: rc', рк, '· назва в помилці:', 'г.md' in е, '· а.md згорнуто:', ост == ['г.md'])
