"""Звірити знімки ДО й ПІСЛЯ; аргументи: ДО ПІСЛЯ [правила, де ефективна вага може змінитись]."""
import collections, gzip, json, sys


def main():
    """Склад, відбиток і сила тотожні; таблиці сирих і ефективних змін ваги."""
    def читати(шлях):
        with gzip.open(шлях, 'rt', encoding='utf-8') as ф:
            return json.load(ф)
    до, після = map(читати, sys.argv[1:3])
    assert len(до) == len(після), (len(до), len(після))
    сирі, ефективні = collections.Counter(), collections.Counter()
    for д, п in zip(до, після):
        assert д[:5] == п[:5], (д, п)
        if д[5] != п[5]:
            сирі[д[2], д[5], п[5]] += 1
        if д[6] != п[6]:
            ефективні[д[2], д[6], п[6]] += 1
    print('знахідок', len(до), '— склад, відбиток і сила тотожні; сирих змін', sum(сирі.values()),
          'ефективних', sum(ефективні.values()))
    for назва, т in (('сирі', сирі), ('ефективні', ефективні)):
        print('\n%s: | правило | ДО | ПІСЛЯ | кількість |' % назва)
        for (правило, було, стало), к in sorted(т.items(), key=str):
            print('| %s | %s | %s | %s |' % (правило, було, стало, к))
    чужі = {k[0] for k in ефективні} - set(sys.argv[3:])
    assert not чужі, чужі


if __name__ == '__main__':
    main()
