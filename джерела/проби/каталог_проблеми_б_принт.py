"""Реєстр проблем каталогу, напрям Б, клас Б7: двоколірні речі й принт описано одним кольором (рядки 234, 631, 1220,
3042, 3150, 3151, 3352). ФАКТ — скільки записів з візерунком, скільки з невідомим візерунком; у скількох «однотонних»
головний кластер кольору менший за 60 % маски чи є другий колір ≥ 30 %; спори візерунка крамниці й фото.
Запуск: cd джерела && python3 -W ignore проби/каталог_проблеми_б_принт.py"""
import collections, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as FK
К = FK._прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"]
віз = collections.Counter(r.get("візерунок") for r in К)
ф = [r for r in К if r.get("колір_hex_фото")]
однот = [r for r in ф if r.get("візерунок") == "solid"]
мала = [r for r in однот if (r.get("колір_частка") or 1) < 0.6]
другий = [r for r in однот if ((r.get("колір_другий") or {}).get("частка") or 0) >= 0.3]
print("ФАКТ · записів %d; з візерунком %d (%.1f %%), однотонних %d, візерунок невідомий %d (%.1f %%); слоти невідомого %s" % (
    len(К), sum(н for в, н in віз.items() if в not in ("solid", None)), 100 * sum(н for в, н in віз.items() if в not in ("solid", None)) / len(К),
    віз["solid"], віз[None], 100 * віз[None] / len(К), collections.Counter(r["слот"] for r in К if not r.get("візерунок")).most_common(4)))
print("ФАКТ · «однотонні» з виміром %d: головний колір < 60 %% маски %d, другий колір ≥ 30 %% %d, хоч одне з двох %d" % (
    len(однот), len(мала), len(другий), len({r["id"] for r in мала + другий})))
сп = collections.Counter((r["візерунок_спір"].get("крамниця"), r["візерунок_спір"].get("фото")) for r in К if r.get("візерунок_спір"))
print("ФАКТ · спір візерунка крамниця→фото: %d, найчастіші %s" % (sum(сп.values()), сп.most_common(4)))
print("ФАКТ · візерунок записано словом (не фото) %d; поле `принт` заповнене у %d записах" % (
    sum(r.get("візерунок_джерело") == "слово" for r in К), sum(bool(r.get("принт")) for r in К)))
