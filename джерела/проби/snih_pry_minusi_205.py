import json, sys, os
sys.path.insert(0, "."); М = "ПІСЛЯ"
import bridge as B, сценарій as СЦ, міст_пакет as МП
# Ч-1 (п.12): рядок жінці — заяви кодами (`повідомлення.statements`), не готова фраза
рядок = lambda x: " + ".join("%s%s" % (з["code"], з.get("values") or "") for з in
                             (((x or {}).get("повідомлення") or {}).get("statements") or [])) or "—"
дж = lambda x: json.dumps(x, ensure_ascii=False)
кан = lambda t: СЦ.канон_опади("так", t) if СЦ.канон_опади.__code__.co_argcount > 1 else СЦ.канон_опади("так")
print("%s · «так» →  %s" % (М, " · ".join("%+d°C %s" % (t, кан(t)) for t in (-8, 0, 3, 16))))
вх0 = json.load(open("стенд_вх.json", encoding="utf-8"))
for т in (-8, 16):
    вх = dict(вх0, сценарій=dict(вх0["сценарій"], нагода="щоденне", місце="парк", темп_c=т, опади="так", дрес_код="casual"))
    МП._КЕШ_ПАКЕТА.clear()
    к = json.loads(B.виклик("запити", дж(вх)))["кандидати"]
    пак = list(МП._КЕШ_ПАКЕТА.values())[-1]
    # ПОГ-1: замша в мокру погоду — умова, не вето; ключ відсічення зі словом «замша» лічить, чи вето десь лишилось
    зн = sum(v for к, v in (пак.get("відсічено") or {}).get("лічба", {}).items() if "замш" in к)
    r = json.loads(B.виклик("від_моделі", дж(dict(вх, ід=[к["сукня"][0]["id"], "ж-10655@emmeliedelage.com",
                                                        "ж-07782@miraton.ua"]))))
    print("%s · %+d°C «так»: пул знімає «замша… у дощ» %d · рядок жінці: %s" % (
        М, т, зн, рядок(r.get("матеріал_жінці"))))
