"""Міряє обрив між доведеним кінцем JSON-пагінації й записом стану обходу."""
import tempfile
from pathlib import Path
from каталог_зависла_крамниця_json_проба import обхід, прогін, порція, РІЧ


def main():
    """Відновлює застарілий або втрачений підсумок без повторних HTTP-запитів."""
    помилки = []
    for сім in ("woo", "shopify"):
        for давній in (True, False):
            with tempfile.TemporaryDirectory(prefix="обрив-json-") as ж:
                прогін(ж, сім, [порція(сім, [РІЧ]), порція(сім, [])])
                if давній:
                    обхід.записати(ж, {"json.test": dict(домен="json.test", стан_код="WAIT",
                        причина_код="EXCEPTION", адрес=0, готово=0, лишилось=1, цикл=1, підстава="обрив")})
                else:
                    (Path(ж) / "обхід_стан.tsv").unlink()
                с, запитів = прогін(ж, сім, [порція(сім, [])])
                добре = с["стан_код"] == "CATALOG" and с["готово"] == "1" and с["лишилось"] == "0"
                добре &= запитів == 0 and с["причина_код"] == ""
                print(f"А/{сім}/давній={давній}: {с['стан_код']}/{с['причина_код']}, "
                      f"готово={с['готово']}, лишилось={с['лишилось']}, запитів={запитів}; добре={добре}")
                помилки.append(not добре)
    return int(any(помилки))


if __name__ == "__main__":
    raise SystemExit(main())
