# -*- coding: utf-8 -*-
"""ОБРАНА ОСНОВА ДОХОДИТЬ ДО ПУЛУ ЧИ ЛИШЕ ДО СЛІВ? (19.09.2026, спостереження власника)

Жінка обрала основу «червоний (теплий)» і схему «нейтрали+акцент», а всі образи вийшли
без жодної червоної речі. Проба міряє шлях обраного кольору в РУЦІ 1: скільки речей сім'ї
основи є В КАТАЛОЗІ (за `колір_образу.сім_я` — тим лексиконом, яким судить код), скільки
доходить до пакета, скільки — у слоти з роллю «акцент». ЩО БУЛО (до правки,
`каталог_повний.xml`, 3 сіди): у каталозі 1004 речі сім'ї «червона/рожева», у пакеті 0 —
`bridge._пакет_каталогу` будував специфікацію БЕЗ `якір_тон`, тож дуга акценту стояла на
тоні ОЧЕЙ (152–192°), а не на основі (30°).
Запуск із теки `джерела`: PYTHONPATH=. python3 проби/kolir_akcent.py"""
import json, pathlib, sys, collections
_К = pathlib.Path(__file__).resolve().parent.parent
if str(_К) not in sys.path: sys.path.insert(0, str(_К))
import bridge as B, colorspace as cs, колір_образу as КО

ВИБІР = dict(база="червоний·тепла·50·насичені", база_hex="#c2554f", база_тип="колір", насиченість="насичені")
СІМ = КО.сім_я(cs.hx(ВИБІР["база_hex"]))
print("основа «%s» %s · сім'я «%s» · тон %.0f°"
      % (ВИБІР["база"], ВИБІР["база_hex"], СІМ, cs.lch(cs.hx(ВИБІР["база_hex"]))[2]))
for сід in (4242, 7, 91):
    вх = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
    вх.update(гілка=2, сід=сід, вибір_кольору=ВИБІР)     # гілка 2 — «нейтрали+акцент»
    r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    пал = json.loads(r["руки"]["1"])["людина"]["палітра"]
    акц = [с for с, роль in (пал.get("ролі_слотів") or {}).items() if роль == "акцент"]
    кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
    у_кат = collections.Counter(c["слот"] for c in кат.values() if c.get("lab") and КО.сім_я(c["lab"]) == СІМ)
    у_пак = collections.Counter()
    for с, v in (r.get("кандидати") or {}).items():
        for x in v:
            lab = (кат.get(x["id"]) or {}).get("lab")
            if lab and КО.сім_я(lab) == СІМ: у_пак[с] += 1
    сім_акц = sum(1 for a in (пал.get("акценти") or []) if КО.сім_я(cs.hx(a.split()[-1])) == СІМ)
    print("сід %-5d схема «%s» · пул %d · акцентних слотів %d · каталог: сім'ї %d (%s)"
          % (сід, пал.get("схема"), r.get("пул_речей") or 0, len(акц),
             sum(у_кат.values()), ", ".join("%s %d" % t for t in у_кат.most_common(4))))
    print("   пакет: сім'ї %d · в акцентних слотах %d · названо моделі акцентів сім'ї %d · ФАКТ акцент обраної сім'ї %s"
          % (sum(у_пак.values()), sum(у_пак[с] for с in акц), сім_акц,
             "Є" if sum(у_пак[с] for с in акц) else "НЕМА"))
