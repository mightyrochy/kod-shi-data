# -*- coding: utf-8 -*-
"""ОБРАНА ОСНОВА ДОХОДИТЬ ДО ПУЛУ ЧИ ЛИШЕ ДО СЛІВ? (19.09.2026, спостереження власника)

Жінка обрала основу «червоний (теплий)» і схему «нейтрали+акцент», а всі образи вийшли без
жодної червоної речі. Проба веде обраний колір крізь РУКУ 1: скільки речей сім'ї основи є в
КАТАЛОЗІ (за `колір_образу.сім_я` — лексиконом, яким судить код), скільки доходить до пакета
і скільки — у слоти з роллю «акцент»; і чи дістає знахідку образ, у якому під цією схемою
жодна річ не несе кольору. ДО ПРАВКИ (`каталог_повний.xml`, сіди 4242/7/91): у каталозі 1004
речі сім'ї «червона/рожева», у пакеті 0 (специфікація пулу будувалась без `якір_тон`, дуга
акценту стояла на тоні ОЧЕЙ 152–192° при основі на 30°), усе-нейтральний образ проходив
мовчки. ПІСЛЯ: 35/37/36 у пакеті, усі в акцентних слотах, і K-COL-03 говорить.
Запуск із теки `джерела`: PYTHONPATH=. python3 проби/kolir_akcent.py"""
import json, pathlib, sys, collections
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path[:0] = [str(_К), str(_К / "проби")]
import bridge as B, colorspace as cs, колір_образу as КО, pal_вердикт as ПВ
ВИБІР = dict(база="червоний·тепла·50·насичені", база_hex="#c2554f", база_тип="колір", насиченість="насичені")
СІМ, _ЛЧ = КО.сім_я(cs.hx(ВИБІР["база_hex"])), cs.lch(cs.hx(ВИБІР["база_hex"]))
print("основа «%s» %s · сім'я «%s» · тон %.0f°" % (ВИБІР["база"], ВИБІР["база_hex"], СІМ, _ЛЧ[2]))
for сід in (4242, 7, 91):
    вх = dict(json.load(open(_К / "стенд_вх.json", encoding="utf-8")), гілка=2, сід=сід, вибір_кольору=ВИБІР)  # гілка 2 — «нейтрали+акцент»
    r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    пал = json.loads(r["руки"]["1"])["людина"]["палітра"]
    акц = [с for с, роль in (пал.get("ролі_слотів") or {}).items() if роль == "акцент"]
    кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
    у_кат = collections.Counter(c["слот"] for c in кат.values() if c.get("lab") and КО.сім_я(c["lab"]) == СІМ)
    у_пак = collections.Counter()
    for с, v in (r.get("кандидати") or {}).items():
        у_пак[с] = sum(1 for x in v if (кат.get(x["id"]) or {}).get("lab") and КО.сім_я(кат[x["id"]]["lab"]) == СІМ)
    print("сід %-5d «%s» · пул %d · акцентних слотів %d · каталог сім'ї %d (%s)\n"
          "   ФАКТ · у пакеті сім'ї %d, з них в акцентних слотах %d (%s)"
          % (сід, пал.get("схема"), r.get("пул_речей") or 0, len(акц), sum(у_кат.values()),
             ", ".join("%s %d" % t for t in у_кат.most_common(4)),
             sum(у_пак.values()), sum(у_пак[с] for с in акц),
             ", ".join("%s %d" % (с, у_пак[с]) for с in акц if у_пак[с]) or "НЕМА"))
вх, r, кат, _сп = ПВ.стенд(гілка=2, вибір_кольору=ВИБІР)
нейтр = lambda с: next((x["id"] for x in (r["кандидати"].get(с) or []) if (кат.get(x["id"]) or {}).get("lab") and КО.нейтраль(кат[x["id"]]["lab"])), None)
ід = [i for i in (нейтр("сукня"), нейтр("взуття"), нейтр("сумка"), нейтр("сережки")) if i]
зн, _ = ПВ.знахідки(вх, ід)
print("ФАКТ · образ із %d нейтралей під «нейтрали+акцент»: K-COL-03 %s" % (len(ід), ПВ.рядок(зн, "K-COL-03")))
