def шляхи(x, п=""):
    if isinstance(x, dict):
        return set().union(*[{п + к} | шляхи(v, п + к) for к, v in x.items()]) if x else set()
    return set().union(*[шляхи(v, п + "[].") for v in x]) if isinstance(x, list) and x else set()
