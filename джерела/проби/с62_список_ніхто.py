"""Проба Н-02-03 (С-62) по списку «ніхто»: читає список З `аудит/ДОСЯЖНІСТЬ.md`
і для кожного імені каже, чи воно ще оголошене в ядрі. Друкує факти.

ЧОМУ СПИСОК ЧИТАЄТЬСЯ, А НЕ ВПИСАНИЙ. Перша версія цієї проби тримала пʼять
імен літералами — і наступний прогін `досяжність.py` побачив їх ГРЕПОМ у цьому
файлі, перевів `міст_http.H.log_message` і `H.do_POST` із «ніхто» в «продукт» і
зменшив список. Тобто проба про мертвий код сама його оживила у звіті — рівно
та підміна, проти якої написані шапки `прилади.py` і `gate_reach.py`. Тепер тут
нема жодного імені: усі беруться з таблиці звіту.

Прогін: python3 проби/с62_список_ніхто.py"""
import ast, io, os, re, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import status

ЗВІТ = os.path.join(ТУТ, "аудит", "ДОСЯЖНІСТЬ.md")
РЯДОК = re.compile(r"^\|\s*`([^`]+)`\s*\|\s*`([^`]+)`\s*\|\s*(\d+)\s*\|\s*(.*?)\s*\|\s*$")


def список_ніхто():
    """(модуль, функція, рядок) з розділу «НІХТО» звіту — саме той перелік,
    який наряд називає своїм входом."""
    у_розділі, вихід = False, []
    for р in io.open(ЗВІТ, encoding="utf-8"):
        if р.startswith("## "):
            у_розділі = "ніхто" in р.lower()
            continue
        if у_розділі:
            з = РЯДОК.match(р.rstrip("\n"))
            if з:
                вихід.append((з.group(1), з.group(2), int(з.group(3))))
    return вихід


def оголошена(модуль, імя):
    """Чи є такий `def` у файлі модуля (метод класу рахується так само)."""
    шлях = модуль + ".py"
    if not os.path.exists(шлях):
        return None
    коротке = імя.split(".")[-1]
    return any(isinstance(в, ast.FunctionDef) and в.name == коротке
               for в in ast.walk(ast.parse(io.open(шлях, encoding="utf-8").read())))


ніхто = список_ніхто()
print("список «ніхто» з аудит/ДОСЯЖНІСТЬ.md: %d імен" % len(ніхто))
у_ядрі = []
for модуль, імя, рядок in ніхто:
    ядро = модуль in status.МОДУЛІ_ПРОДУКТУ
    print("  %-18s %-42s :%-5d ядро: %-4s оголошена: %s"
          % (модуль, імя, рядок, "так" if ядро else "ні",
             {True: "так", False: "нема", None: "файлу нема"}[оголошена(модуль, імя)]))
    # «У ЯДРІ» = і в списку вантажу, і ЩЕ ОГОЛОШЕНА. Ім'я, якого в модулі вже
    # нема (знесено або винесено в лабораторію), у ядрі не важить нічого — звіт
    # просто старіший за дерево.
    if ядро and оголошена(модуль, імя):
        у_ядрі.append("%s.%s" % (модуль, імя))
print()
print("«НІХТО» У ЯДРІ (status.МОДУЛІ_ПРОДУКТУ) — приймання наряду:",
      у_ядрі or "жодного")

import status_перевірки as SP
