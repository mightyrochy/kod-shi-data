"""Проба: заперечення в опорі речення — лише дослівно в полях моделі (рішення 14177, корінь Е2-межі).

Доти суд сам читав «не/ні/без/жодн» у реченні (п.7 класу); тепер модель дає `her_words` (і стан поля `recorded`),
а код звіряє їх з уривком дослівно — цілими словами. Шматок із запереченням, якого нема в уривку, — без опори; шматок уривка — опора; чи речення каже те саме, що
шматок, — тлумачення моделі. Друкує по парі: прийнято за уривком, за чужим шматком, у суді репліки й у показі ходу.
"""
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import мовний_шар as м


def суди(текст, уривок, мітка, шматок):
    """Той самий текст і шматок — у суді речення, репліки й показі ходу."""
    картка = dict(goal=dict(label=мітка or уривок, quote=уривок, source='her'))
    ч = dict(about=['goal'], recorded=['goal'], her_words=[шматок], says=текст)
    return [bool(м.суд_підтвердження(ч, картка)[0]), bool(м.суд_репліки([ч], dict(recorded=картка))[0]),
            bool(м._текст_до_показу(dict(text_parts=[ч]), картка, картка=картка)[0])]


def main():
    """Свій шматок (із запереченням, як в уривку) — прийнято; чужий шматок — ні, в усіх трьох судах."""
    пари = [('не хочу виділятись', 'Непомітно', 'Не хочу виділятись.', 'не хочу виділятись', 'хочу виділятися'),
            ('образ без підборів', '', 'Образ без підборів.', 'без підборів', 'з підборами'),
            ('жодних підборів', '', 'Жодних підборів.', 'жодних підборів', 'жодні підбори'),
            ('не театр', 'Театр', 'Не театр.', 'не театр', 'не концерт')]
    виміри = [dict(уривок=у, свій=суди(т, у, мітка, свій), чужий=суди(т, у, мітка, чужий))
              for у, мітка, т, свій, чужий in пари]
    print(json.dumps(виміри, ensure_ascii=False))
    assert all(all(в['свій']) and not any(в['чужий']) for в in виміри)


if __name__ == '__main__':
    main()
