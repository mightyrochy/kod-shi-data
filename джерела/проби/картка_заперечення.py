"""Проба втрати й перенесення заперечення у спільному суді та його читачах."""
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import картка_запиту as к
import мовний_шар as м
def суди(текст, уривок, мітка):
    """Виміряти той самий текст у зіставленні, підтвердженні, перекладі й показі."""
    картка = dict(goal=dict(label=мітка, quote=уривок, source='her'))
    частини = dict(text_parts=[dict(about=['goal'], says=текст)])
    return [bool(к.зіставити_підтвердження(текст, [уривок], мітки=[мітка])[0]),
            bool(м.суд_підтвердження(текст, картка)[0]),
            bool(м.суд_репліки(текст, dict(recorded=картка))[0]),
            bool(м._текст_до_показу(частини, картка, картка=картка)[0])] + [
            bool(м.суд_репліки(текст, {поле: уривок})[0]) for поле in ('answer', 'added', 'item_verdicts')]


def main():
    """Надрукувати ДО/ПІСЛЯ для кожної пари; провал завершує лише цю пробу."""
    пари = [
        ('не хочу виділятись', 'Непомітно', 'Хочу виділятись.', 'Не хочу виділятись.'),
        ('не люблю підбори', '', 'Люблю підбори.', 'Не люблю підбори.'),
        ('образ без підборів', '', 'Образ підборів.', 'Образ без підборів.'),
        ('жодних підборів', '', 'Підборів.', 'Жодні підбори.'),
        ('ні блиску', '', 'Блиску.', 'Ні блиску.'),
        ('не театр', 'Театр', 'Театр.', 'Не театр.'),
        ('не хочу підборів, хочу кеди', '', 'Хочу підборів, не хочу кеди.', 'Не хочу підборів, хочу кеди.'),
        ('без блиску, люблю кеди', '', 'Люблю блиск, без кедів.', 'Без блиску, люблю кеди.'),
        ('жодного блиску, люблю принти', '', 'Люблю блиск, жодних принтів.', 'Жодного блиску, люблю принти.'),
        ('не хочу ні блиску ні підборів', '', 'Не хочу блиску підборів.', 'Не хочу ні блиску ні підборів.'),
    ]
    виміри = [dict(уривок=у, без_заперечення=суди(б, у, мітка), зі_запереченням=суди(з, у, мітка))
              for у, мітка, б, з in пари]
    print(json.dumps(виміри, ensure_ascii=False, indent=1))
    assert all(not any(в['без_заперечення']) and all(в['зі_запереченням']) for в in виміри)


if __name__ == '__main__':
    main()
