"""Звіряє стан талії у маршруті, ролях зон, обох дротах і напрузі гіперграфа."""
import os, sys, json
from pathlib import Path
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import fit as ПС, silhouette as С, hypergraph as Г, дріт_моделі as Д, accessory as А


if __name__ == '__main__':
    корінь = Path(__file__).resolve().parents[2]
    випадки = []
    for ж, ярлик in ((8, 'H'), (7, 'H'), (6, 'V'), (4, 'H')):
        м = json.loads((корінь / 'аудит/проби/жінки' / ('ж%d.json' % ж)).read_text(encoding='utf-8'))['мірки']
        випадки.append((str(ж), м.pop('зріст'), м, ярлик, False))
    випадки += [('невідомо', 168, dict(плечі=91.44, груди=91.44, талія=76.2, стегна=99.06), 'A', None),
                ('невідомо рівно', 168, dict(плечі=99, груди=91.44, талія=76.2, стегна=99.06), 'H/X межа', None),
                ('спільний стан', 168, dict(плечі=101.6, груди=91.44, талія=76.2, стегна=101.6), 'X', True),
                ('O', 168, dict(плечі=100, груди=100, талія=106, стегна=100), 'O', False)]
    for назва, зріст, обхвати, ярлик, стан in випадки:
        т = ПС.тіло(зріст, обхвати)
        з = ПС.зони(т)
        assert з['ярлик'] == ярлик and з['вектор']['талія_виражена'] is стан, (назва, з)
        роль = С.ролі_зон(т)['ролі']['талія']
        assert роль == ('виражена' if стан is True else 'невиражена' if стан is False else None)
        напруга = next(р['напруга'] for р in Г.ребра(т) if р['ід'] == 'якір_обʼєму')
        assert напруга == (С.C['підлога_напруги_ребра'] if стан is True else 1)
        if ярлик == 'H/X межа':
            простір = Г.простір(т)
            assert простір['живих'] > 0 and простір['блокованих'] == 0
            assert простір['без_влучання'] > 0 and простір['живих'] + простір['без_влучання'] <= простір['оцінено']
        тіло = Г.тіло_для_опису(т)
        for дріт in (Д.людина({'тіло': dict(ярлик=з['ярлик'], зони=з['вектор'])}), Д.опис({'тіло': тіло})):
            assert дріт['body']['zones']['waist_defined'] is стан
            assert дріт['body']['zones']['waist_basis'] == з['вектор']['талія_підстава']
        зн = А.передумови_пояса(т, [{'слот': 'пояс', 'назва': 'пояс'}])
        assert (not зн) if стан is True else (зн and (стан is not None or зн[0]['сила_нп'] == 0))
        print(назва, '→', ярлик, стан, роль, напруга, з['вектор']['талія_підстава'])
