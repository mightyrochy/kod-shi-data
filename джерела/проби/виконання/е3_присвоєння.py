"""Знімок ваги знахідок 13 місць присвоєння Е3-сила-правила (наряд Е3-сила-правила-вага-присвоєння).

Аргументи: вихід `.json.gz`, тека `джерела/` дерева (ДО — робоче дерево бази, ПІСЛЯ — голова), частини через кому
(`каталог`, `межі`, `гейти`, `дим`). Обгортає функції з місцями приладу в усіх модулях і таблицях модулів,
записує кожну повернену знахідку: сира вага й вага після `обмежити_вагу` (з позначкою підлоги)."""
import functools, gzip, inspect, json, os, pathlib, runpy, sys, time, traceback

ЦІЛІ = {'колір_нейтралі': ('температура_нейтралі', 'бік_b_біля_обличчя'), 'палітра_запити': ('макіяж_тон_у_тон',),
        'силует_пропорції': ('об_єм',), 'суд_від_моделі': ('нижче_смуги_образу', 'перевірити_від_моделі'),
        'розбір_відповідей': ('застосувати_свідомі',),
        'поломки': ('_каблук_вищий', '_акцент_нейтраллю', '_метал_навпаки', '_тканина_навпаки')}
# K-COMP-07 — свій вимір; чотири правила — гілка наміру statement (`суд_від_моделі.py`, 15636)
ПЕРЕВІРКА_ВІД_МОДЕЛІ = ('K-COMP-07', 'K-COL-02', 'K-COMP-04', 'K-INT-04', 'K-COMP-03')
ОСОБИ = (('#deb295', '#f1dbaa', '#759087'), ('#f3d6cf', '#3b3b45', '#6f8fb5'))   # тепла й холодна
МАКІЯЖ = ('#d9a0a0', '#8b2232', '#c46a4f', '#6b4a6e', '#e8c4b0')


def main():
    вихід, тека = sys.argv[1], os.path.abspath(sys.argv[2])
    частини = (sys.argv[3] if len(sys.argv) > 3 else 'каталог,межі,намір,гейти,дим').split(',')
    sys.path.insert(0, тека)
    os.chdir(тека)
    import importlib
    from реєстр_сила import обмежити_вагу
    записи, мітка = [], ['']

    def запис(ф, з):
        еф = обмежити_вагу([dict(з)])[0]
        записи.append([мітка[0], ф, з.get('правило'), str(з.get('суть')), json.dumps(з.get('речі'), ensure_ascii=False,
                       default=str), з.get('сила'), bool(з.get('блокує')), з.get('сила_нп'), еф.get('сила_нп'),
                       bool(еф.get('під_підлогою'))])

    def обгорнути(ф):
        @functools.wraps(ф)
        def виклик(*a, **k):
            р = ф(*a, **k)
            if ф.__name__ == 'перевірити_від_моделі' and isinstance(р, dict):
                for з in р.get('акцент') or []:
                    if isinstance(з, dict): запис('перевірити_від_моделі/акцент', з)
                for з in р.get('знахідки') or []:
                    if isinstance(з, dict) and з.get('правило') in ПЕРЕВІРКА_ВІД_МОДЕЛІ: запис(ф.__name__, з)
                return р
            for з in (р[0] if isinstance(р, tuple) else р) if isinstance(р, (list, tuple)) else []:
                if isinstance(з, dict) and 'правило' in з: запис(ф.__name__, з)
            return р
        return виклик

    заміни = {}
    for мод, імена in ЦІЛІ.items():
        м = importlib.import_module(мод)
        for ім in імена:
            заміни[id(getattr(м, ім))] = обгорнути(getattr(м, ім))
    for м in list(sys.modules.values()):
        for к, з in list(vars(м).items()) if м and hasattr(м, '__dict__') else []:
            if id(з) in заміни: setattr(м, к, заміни[id(з)])
            elif isinstance(з, dict) and not inspect.ismodule(з):
                for кк, зз in list(з.items()):
                    if id(зз) in заміни: з[кк] = заміни[id(зз)]
    М = {мод: importlib.import_module(мод) for мод in ЦІЛІ}
    if 'каталог' in частини: каталог(М, мітка)
    if 'межі' in частини: межі(М, мітка)
    if 'намір' in частини: намір(мітка)
    провали = []
    if 'гейти' in частини or 'дим' in частини:
        скрипти = ([('прилади/розділи_гейтів.py', [])] if 'гейти' in частини else []) + (
            [('стенд_знімок.py', ['--дим']), ('тест_живого_шляху.py', []), ('тест_протоколу.py', [])]
            if 'дим' in частини else [])
        журнал = open(вихід + '.log', 'w', encoding='utf-8', buffering=1)
        for скрипт, арг in скрипти:
            мітка[0] = скрипт; sys.argv = [скрипт, *арг]; шляхи = list(sys.path)
            sys.path.insert(0, str(pathlib.Path(тека, скрипт).parent)); os.chdir(тека)
            старт, код, (о, е) = time.monotonic(), 0, (sys.stdout, sys.stderr)
            sys.stdout = sys.stderr = журнал
            try: runpy.run_path(скрипт, run_name='__main__')
            except SystemExit as з: код = з.code or 0
            except BaseException: код = 1; traceback.print_exc()
            finally: sys.stdout, sys.stderr = о, е; sys.path[:] = шляхи
            print(скрипт, 'код', код, '%.0f с' % (time.monotonic() - старт), flush=True)
            if код: провали.append([скрипт, код])
    with gzip.open(вихід, 'wt', encoding='utf-8') as ф:
        json.dump(dict(записи=записи, провали=провали), ф, ensure_ascii=False)
    print('записів', len(записи), 'провали', провали)


def каталог(М, мітка):
    """Кожна річ повного каталогу біля обличчя × дві особи, два боки очей × дві довіри, п'ять кольорів
    макіяжу, чотири рівні ошатності × без пояснення / з поясненням / її бажання."""
    import feed as Ф, outfit as О, colorspace as Ц
    кеш = pathlib.Path(os.environ.get('TMP', '/tmp'), 'е3_присвоєння_каталог.json.gz')
    if кеш.exists():
        with gzip.open(кеш, 'rt', encoding='utf-8') as ф: кат = json.load(ф)
    else:
        кат = Ф.база_прогону(Ф.каталог_на_диску('каталог_повний.xml'), ліміт_фото=0)['каталог']
        with gzip.open(кеш, 'wt', encoding='utf-8') as ф: json.dump(кат, ф, ensure_ascii=False)
    print('каталог', len(кат), flush=True)
    за_ід = {р['id']: р for р in кат}
    особи = [Ц.features(*(Ц.hx(х) for х in о)) for о in ОСОБИ]
    КН, ПЗ, СВМ = М['колір_нейтралі'], М['палітра_запити'], М['суд_від_моделі']
    for н, р in enumerate(кат):
        мітка[0] = 'каталог'
        р2 = dict(р, місце_стилістки=dict(біля_обличчя='так', слова='як вдягнено'))
        try:
            е = О.елементи([р2])[0]
        except Exception:
            continue
        for о in особи:
            КН.температура_нейтралі([dict(е)], о, драп=dict(метал='золото', нейтралі='теплі'), речі=[р2])
        for бік in (1, -1):
            for дов in (1.0, 0.55):
                КН.бік_b_біля_обличчя([dict(е)], {}, _бб=dict(вхід=True, бік=бік, b_очей=10 * бік, довіра=дов))
        ПЗ.макіяж_тон_у_тон([dict(е)], {'м%d' % і: dict(рід='обрана', hex=х, зона='губи') for і, х in enumerate(МАКІЯЖ)})
        for рів in (4, 6, 7, 9):
            сц = dict(ошатність=[рів, рів], _ошатність=[рів, рів], пора='день')
            СВМ.нижче_смуги_образу([р['id']], за_ід, сц)
            СВМ.нижче_смуги_образу([р['id']], за_ід, сц, свідомі=[dict(ід=р['id'], текст='свідомо')])
            СВМ.нижче_смуги_образу([р['id']], за_ід, сц, кандидати={'x': [dict(р, за_бажанням=True)]})
        if н % 5000 == 0: print('річ', н, flush=True)


def намір(мітка, образів=800):
    """Образи з повного каталогу (верх, низ, взуття, сумка — сідом) під наміром statement і типовим
    через `pipeline.перевірити_від_моделі`: гілка наміру statement (K-COL-02, K-COMP-04, K-INT-04, K-COMP-03)."""
    import random, bridge as Б, pipeline as P
    with gzip.open(pathlib.Path(os.environ.get('TMP', '/tmp'), 'е3_присвоєння_каталог.json.gz'), 'rt',
                   encoding='utf-8') as ф:
        кат = json.load(ф)
    за_слотом = {}
    for р in кат:
        за_слотом.setdefault(р.get('слот'), []).append(р)
    вх = dict(шкіра='#deb295', волосся='#f1dbaa', очі='#759087', зріст=167,
              обхвати={'плечі': 98, 'груди': 90, 'талія': 72, 'стегна': 100, 'коліно': 37, 'литка': 35})
    F, T = Б._збірка(вх)[:2]
    в = random.Random(20261115)
    for н in range(образів):
        речі = [в.choice(за_слотом[с]) for с in ('верх', 'низ', 'взуття', 'сумка') if за_слотом.get(с)]
        for intent in ('statement', 'conventional'):
            мітка[0] = 'намір ' + intent
            try:
                P.перевірити_від_моделі([р['id'] for р in речі], F, речі, T,
                                        dict(нагода='побачення', intent=intent))
            except Exception as з:
                print('намір', н, intent, type(з).__name__, з)
        if н % 200 == 0: print('образ', н, flush=True)


def межі(М, мітка):
    """Граничні входи без каталогу: кожна сира вага 0.01…1.00 під свідомим ходом; ручні вхідні зламаних правил."""
    мітка[0] = 'межі'
    РВ, П = М['розбір_відповідей'], М['поломки']
    for ст in ('hint', 'soft', 'default', 'strong'):
        for в in range(1, 101):
            РВ.застосувати_свідомі([dict(правило='K-KOH-02', сила=ст, сила_нп=в / 100, речі=['a'], суть='x')],
                                   [dict(текст='свідомо', правило='K-KOH-02', ід='a')], [dict(id='a', назва='a', слот='верх')])
    р = dict(id='a', слот='взуття', назва='a')
    for h in range(0, 13):
        for год in (1, 2, 4, 6, 8, 12):
            for коеф in (0.5, 0.8, 1.0, 1.2, 1.5):
                П._каблук_вищий([], р, float(h), год, коеф)
    for слот in ('сумка', 'шарф', 'взуття'):
        П._акцент_нейтраллю([], dict(id='a', слот=слот), слот, 20.0)
    for near in (0, 0.1, 0.25, 0.3, 0.5, 0.75, 1.0):
        вед = dict(річ='a', id='a', метал='золото', слот='сережки', місце_речі=dict(біля_обличчя=near, джерело='вимір'), near=near)
        for кв, т in (('теплий', 0.4), ('холодний', -0.4), ('теплий', -0.4), ('холодний', 0.4)):
            try:
                П._метал_навпаки([], 0, вед, кв, lambda т=т: т)
            except Exception as з:
                print('метал', near, кв, т, type(з).__name__, з)
    for смуга in ('deep_frost', 'frost', 'cold', 'cool', 'mild', 'warm', 'hot'):
        П._тканина_навпаки([], dict(річ='a', id='a', слот='верх'), смуга)


if __name__ == '__main__':
    main()
