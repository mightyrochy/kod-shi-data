# -*- coding: utf-8 -*-
"""Ч-3 (п.9 «звіт без стелі», п.12): ЩО ВЕЗЕ КОЛОНКА ЗВІТУ `знахідки_коду`. Той самий шлях,
що в показі (`запити` → `від_моделі` → `в.знахідки`), 6 сценаріїв × 4 форми образу. Лічить
знахідки суду й скільки з них несуть кожне поле, яке `показ.html` мапить у колонку: `ремонт`
(єдине, що каже ЩО РОБИТИ), `чому`, `також_правила`, `заяви` (внутрішня мова поруч із прозою)
і `ід` (його цей перелік не має за побудовою). Запуск із `джерела`:
python3 проби/звіт_знахідки_поля.py"""
import collections, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import feed; feed.каталог_на_диску("каталог_повний.xml")
import bridge as B, стенд_знімок as СЗ
ФОРМИ = [("верх", "низ", "взуття", "сумка"), ("сукня", "взуття", "сумка"),
         ("верх", "низ", "верхній_шар", "взуття", "сумка", "шарф"),
         ("комплект", "взуття", "сумка", "намисто", "каблучка")]
вх0 = json.load(open("стенд_вх.json"))
зн = []
for назва, сц in list(СЗ.СЦЕНАРІЇ.items())[:6]:
    вх = dict(вх0, сценарій=сц, випадок=назва)
    к = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False))).get("кандидати") or {}
    for ф in ФОРМИ:
        ід = [к[с][0]["id"] for с in ф if к.get(с)]
        зн += json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід),
                                                           ensure_ascii=False))).get("знахідки") or []
поля = collections.Counter(п for з in зн for п in ("суть", "чому", "ремонт", "також_правила", "заяви", "ід")
                           if з.get(п) not in (None, "", [], {}))
print("знахідок суду у звіті: %d · різних правил: %d" % (len(зн), len({з.get("правило") for з in зн})))
for п in ("суть", "чому", "ремонт", "також_правила", "заяви", "ід"):
    print("  %-14s несуть %4d з %4d (%3d %%)" % (п, поля[п], len(зн),
                                                 round(100.0 * поля[п] / max(1, len(зн)))))
