# -*- coding: utf-8 -*-
"""Рядок 5621 (реєстр 5616, клас Г2): каталог — вибірка, а не асортимент. Зі зведення прогонів жнив друкує, чим
скінчився кожен прогін крамниці (стеля карток, бюджет секунд, нуль, збій) і скільки адрес знайдено проти відкритих.
Запуск: python3 джерела/проби/каталог_проблеми_г_стеля.py"""
import collections, os, re                                                     # noqa: E401
Ф = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "zhnyvarka", "зведення_жнив.tsv")
рядки = [р.rstrip("\n").split("\t") for р in open(Ф, encoding="utf-8")]
ш = рядки[0]; рядки = [р for р in рядки[1:] if len(р) >= 12 and re.match(r"\d{4}-\d\d-\d\d$", р[0])]  # noqa: E702
І = {к: ш.index(к) for к in ("дата", "домен", "транспорт", "адрес_знайдено", "відкрито", "карток", "збоїв", "нотатка")}
чим = collections.Counter()
for р in рядки:
    н = р[І["нотатка"]] if len(р) > І["нотатка"] else ""
    чим["0 карток" if р[І["карток"]] == "0" else "бюджет секунд вичерпано" if "бюджет" in н
        else "стеля карток" if "стеля" in н else "дійшов до кінця"] += 1
print("прогонів крамниць: %d (дат %s, транспорт %s)" % (len(рядки), sorted({р[0] for р in рядки}),
      dict(collections.Counter(р[І["транспорт"]] for р in рядки))))
for к, ч in чим.most_common():
    print("  %-26s %3d" % (к, ч))
с = lambda к: sum(int(р[І[к]] or 0) for р in рядки)                            # noqa: E731
print("адрес знайдено %d · відкрито %d (%.0f %%) · карток %d · збоїв %d" % (с("адрес_знайдено"), с("відкрито"),
      100 * с("відкрито") / max(с("адрес_знайдено"), 1), с("карток"), с("збоїв")))
