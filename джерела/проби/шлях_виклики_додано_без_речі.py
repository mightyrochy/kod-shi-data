# -*- coding: utf-8 -*-
"""Розбір шляху 4/8 · «Додано взуття» без взуття (p329 s7, рука 2: «виконано» на всіх п'яти образах каже
«Додано взуття…», а в «речі» взуття нема, лофери — у «потрібно» при 8 парах вітрини). Складання: 5 образів без
взуття; ремонт повертає їх так само без взуття, із заявою «виправлено» і «день» «Додано взуття…». Друкує: що
код каже про кожну заяву («виконання»), чи має блокер «нема_взуття» ід, на який модель могла б послатись, що
пішло з «потрібно» в пул, і що з «день» доходить до промпта опису. Запуск: cd джерела && python3 проби/шлях_виклики_додано_без_речі.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), варіантів=10, ремонт_варіантів=5, бюджет_символів=120000, без_фото=1)
пул = json.loads(json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["руки"]["1"])["пул"]
н = lambda с, k: пул[с][k % len(пул[с])]["н"]
від = lambda т, **д: json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=т, **д), ensure_ascii=False)))
образи = [dict(ід="о%d" % (і + 1), підпис="беж", день="Офіс.", речі=[н(с, і) for с in ("верх", "низ", "сумка", "пояс")]) for і in range(5)]
в1 = від(json.dumps(dict(версія="1", образи=образи), ensure_ascii=False))
пр = json.loads(в1["промпт_ремонту"])
бл = пр["вердикт"][0]["структура"]["блокери"]
print("ремонт бачить: блокери о1 %s · поле «ід» у блокера: %s · у вітрині взуття %d" % ([б["код"] for б in бл], ["ід" in б for б in бл], len(пр["вітрина"].get("взуття") or [])))
for о in образи:
    о["день"] = "Додано взуття для ходи."
    о["виконано"] = [dict(знахідка="нема_взуття", дія="виправлено", чому="Додано взуття: лофери"),
                     dict(знахідка="з-%s-1" % о["ід"], дія="виправлено", чому="Додано взуття")]
в2 = від(json.dumps(dict(версія="1", образи=образи, потрібно=[dict(слот="взуття", опис="лофери шкіряні")]), ensure_ascii=False),
         ітерація=2, попередній_вердикт=в1["вердикт"])
о1 = в2["вердикт"]["образи"][0]
for в in о1.get("виконання") or []:
    print("заява «%s» на %s → перевірено %s · %s" % (в["дія"], в["знахідка"], в["перевірено"], в["чому"][:110]))
print("після ремонту: блокери о1 %s · з «потрібно» додано в пул %d речей, в образи 0" % ([б["код"] for б in о1["структура"]["блокери"]], len(в2.get("запропоновано") or [])))
print("повнота: ід %d, повний %s · промпт повноти %d симв." % (len((в2.get("повнота") or {}).get("ід") or []), (в2.get("повнота") or {}).get("повний"), len(в2.get("промпт_повноти") or "")))
о = json.loads(B.виклик("опис", json.dumps(dict(вх, речі=(в2.get("повнота") or {}).get("ід"), день=(в2.get("повнота") or {}).get("день") or ""), ensure_ascii=False)))  # показ шле «день» з рішення про картку (Л-4)
п = json.loads(о["промпт"])
print("промпт опису: слоти %s · день_образу «%s»" % (sorted({r.get("слот") for r in п["образ"]["речі"]}), п.get("день_образу")))
