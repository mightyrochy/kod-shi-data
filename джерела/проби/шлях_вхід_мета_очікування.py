# -*- coding: utf-8 -*-
"""Л-3б (В-2, В-13): РЯДОК МЕТИ НА ЕКРАНІ ОЧІКУВАННЯ ВИДАВАВ ВШИТЕ ЧИСЛО ФОРМИ ЗА ЇЇ ФАКТ.
Друкує КОЖНОГО читача `сц-година`/`сц-темп` у `показ.html`: у якій він функції і чи питає
ознаку `ТИПОВІ_НЕ_РУКОЮ_П` (поле, якого рука не торкалась). ДО правки `малюватиМету` читала
поля напряму, і на екрані очікування жирним стояли «11:00» і «+18 °C» про день, про який
жінка не сказала нічого; ПІСЛЯ — той самий гейт, що у `випадокРядком`, а названі плиткою
опади лишаються словом плитки. Запуск із теки `джерела`: `python3 проби/шлях_вхід_мета_очікування.py`."""
import sys, os, re
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
html = open("показ.html", encoding="utf-8").read()
рядки = html.split("\n")
функція, де = {}, None
for н, р in enumerate(рядки, 1):
    м = re.match(r"function\s+([\wА-Яа-яіїєґІЇЄҐ_]+)\s*\(", р)
    if м: де = м.group(1)
    функція[н] = де

for ід in ("сц-година", "сц-темп"):
    m = re.search(r'id="%s"[^>]*value="([^"]*)"' % ід, html)
    print("форма: <input id=%s> вшите value=%s" % (ід, m.group(1) if m else "—"))
print()
ворота = 0
for н, р in enumerate(рядки, 1):
    if not re.search(r"\$\('(сц-година|сц-темп)'\)\.value", р): continue
    є = "ТИПОВІ_НЕ_РУКОЮ_П" in р
    ворота += є
    print("%-28s рядок %-5d ознака «рука не торкалась»: %s" % (функція[н] or "?", н, "так" if є else "НІ"))

тіло = html.split("function малюватиМету(", 1)[1].split("\nfunction ", 1)[0]
print("\nмалюватиМету: гейт години=%s, гейт градусів=%s, опади словом плитки=%s"
      % ("ТИПОВІ_НЕ_РУКОЮ_П.has('сц-година')" in тіло, "ТИПОВІ_НЕ_РУКОЮ_П.has('сц-темп')" in тіло,
         "ОПАДИ.find" in тіло))
print("неторкана форма ДО:    пункти «погода +18 °C» і «година 11:00» — як її факт")
print("неторкана форма ПІСЛЯ: цих пунктів нема; числа лишаються на екрані сценарію й на його картці")

assert "ТИПОВІ_НЕ_РУКОЮ_П.has('сц-темп')" in тіло and "ТИПОВІ_НЕ_РУКОЮ_П.has('сц-година')" in тіло, \
    "рядок мети досі читає вшите число форми як її факт (В-2 живий на екрані очікування)"
assert "ОПАДИ.find" in тіло, "названі плиткою опади зникають разом із неназваними градусами"
assert ворота >= 4, "гейт зник з одного з читачів для людини"
print("\nЛ-3б: вшите число форми як її факт на екрані очікування — нема")
