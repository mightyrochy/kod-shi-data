# -*- coding: utf-8 -*-
"""Л-3б і Л-3б-2 (В-2, В-13): ХТО В `показ.html` ЧИТАЄ ВШИТЕ ЧИСЛО ФОРМИ І ЧИ ПИТАЄ ОЗНАКУ.
Друкує КОЖНУ функцію, що читає `сц-темп`, і чи питає вона `типовеЧислоП` (поле, якого рука не торкалась і якого
не назвала розмова). Поле «Коли» — вибір частини дня без типового (`сц-пора`, корінь Е2-частина-дня): ознаки йому
не треба, вшитої години нема. Хто КАЖЕ — жінці чи моделі —
мусить питати; хто лише ВИРІШУЄ всередині коду, названий тут винятком із причиною.
ДО: рядок мети на очікуванні (`малюватиМету`) і рядок стану для помічниці
(`рядокСценаріюСловами` → `станДляШі`) видавали 11:00 і +18 °C за її факт. ПІСЛЯ: мета їх не
називає, стан несе з походженням (П-4: поля `зібратиВхід().сценарій` з `типові_поля`, у дроті
моделі — `form_defaults`, `міст_помічниця.стан`). Запуск із теки `джерела`:
`python3 проби/шлях_вхід_мета_очікування.py`."""
import sys, os, re, glob
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
# показ — розмітка й модулі `показ/*.js` (скрипти давно не вшиті в `показ.html`)
html = "".join(open(ф, encoding="utf-8").read() for ф in ["показ.html"] + sorted(glob.glob("показ/*.js")))
# тіло кожної функції: від `function ім'я(` до наступної `function` на початку рядка
ТІЛА, ІМЕНА = {}, re.findall(r"(?m)^function\s+([\wА-Яа-яіїєґІЇЄҐ_]+)\s*\(", html)
for і, імʼя in enumerate(ІМЕНА):
    поч = html.index("\nfunction %s(" % імʼя)
    далі = html.find("\nfunction ", поч + 1)
    ТІЛА[імʼя] = html[поч:далі if далі > 0 else len(html)]
for ід in ("сц-пора", "сц-темп"):
    m = re.search(r'id="%s"[^>]*value="([^"]*)"' % ід, html)
    print("форма: <input id=%s> вшите value=%s" % (ід, m.group(1) if m else "—"))
print()
без_воріт = []
# Читачі, що лише ВИРІШУЮТЬ усередині коду й числа нікому не переказують, — винятки з причиною
ВИНЯТКИ = {"рукаТоркнуласьП": "дотик руки: число вже її, плитку відчуття знімає",
           "обратиВідчуттяП": "плитка відчуття знімає число поля, не називаючи його",
           "застосуватиПаспортДоЕкранаВтіло": "дощ чи сніг усередині коду (K-WEA-01)"}
for імʼя, тіло in ТІЛА.items():
    if not re.search(r"\$\('сц-темп'\)\.value", тіло): continue
    є = "типовеЧислоП" in тіло
    if not є and імʼя not in ВИНЯТКИ: без_воріт.append(імʼя)
    print("%-28s питає ознаку: %s" % (імʼя, "так" if є else "НІ"))

# Єдине читання без гейта на самому рядку — `застосуватиПаспортДоЕкрана`: температурою вона
# розрізняє дощ і сніг усередині коду (K-WEA-01), нікому цього числа не переказуючи; ознаку
# ця сама функція веде (ставить і знімає з `джерело_полів`), тож у переліку вона «так».
мета, стан = ТІЛА["малюватиМету"], ТІЛА["станДляШі"]
print("\nмалюватиМету:          гейт обох чисел=%s, опади словом плитки=%s"
      % ("типовеЧислоП('сц-темп')" in мета,
         "ОПАДИ.find" in мета))
print("станДляШі:             поля сценарію з походженням (`зібратиВхід().сценарій`, `типові_поля`)=%s"
      % ("зібратиВхід().сценарій" in стан))
print("неторкана форма ДО:    мета «погода +18 °C», «година 11:00»; стан помічниці «… 11:00 · +18 °C»")
print("неторкана форма ПІСЛЯ: мети цих пунктів нема; стан — {темп_c: 18, типові_поля: [темп_c]}, частини дня без вибору нема")

assert not без_воріт, "вшите число форми читають без ознаки: %s" % ", ".join(без_воріт)
assert "типовеЧислоП('сц-темп')" in мета and "сц-година" not in мета, \
    "рядок мети досі видає вшите число форми за її факт"
assert "ОПАДИ.find" in мета, "названі плиткою опади зникають разом із неназваними градусами"
assert "зібратиВхід().сценарій" in стан, "стан для помічниці несе вшите число без походження"
print("\nЛ-3б/Л-3б-2: читача вшитого числа форми без ознаки — нема")
