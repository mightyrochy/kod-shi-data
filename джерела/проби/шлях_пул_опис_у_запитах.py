# -*- coding: utf-8 -*-
"""Розбір 3/8: де річ їде номером чи сирим id БЕЗ опису (рішення власника: «речі,
які отримує функціональна модель, — завжди з повним описом»).

Рахує в кожному запиті руки 1 прогону власника 25.09 (розклад 4123): згадки
номера пулу «#N·MM» — обʼєктом речі з `назва` чи голим номером без опису — і
згадки СИРОГО id крамниці («ж-08489@sunwin-store.com»), де опису нема зовсім.
Прогін: python3 проби/шлях_пул_опис_у_запитах.py
"""
import json, os, re
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ФАЙЛ = os.path.join(os.path.dirname(ТУТ), "аудит", "тести", "власник_2026-09-25",
                    "verdykty-0phxvk-2026-09-25-2012.json")
НОМЕР, ІД = re.compile(r"#\d+·\d\d"), re.compile(r"[а-яїієґ]-\d{4,}@[\w.\-]+")

def обʼєкти(вузол, л):
    """Скільки номерів стоять обʼєктом речі — з полем `назва` і без нього."""
    if isinstance(вузол, dict):
        if НОМЕР.fullmatch(str(вузол.get("н") or "")):
            л["з описом" if вузол.get("назва") else "без назви"] += 1
        for v in вузол.values():
            обʼєкти(v, л)
    elif isinstance(вузол, list):
        for v in вузол:
            обʼєкти(v, л)


for пр in json.load(open(ФАЙЛ, encoding="utf-8"))["прогони"]:
    for в in пр["вердикти"]:
        for c in ((в.get("етапи") or {}).get("виклики") or []):
            т = (c.get("запит") or {}).get("текст") or "" if isinstance(c.get("запит"), dict) else ""
            if not т.startswith("{"):
                continue
            л = {"з описом": 0, "без назви": 0}
            обʼєкти(json.loads(т), л)
            всього = len(НОМЕР.findall(т))
            print("рука %s · %-22s %6d симв | згадок номера %3d: обʼєктом з описом %3d, обʼєктом "
                  "без назви %3d, ГОЛИМ номером %3d | сирих id крамниць %3d"
                  % (в.get("рука"), c.get("крок"), len(т), всього, л["з описом"], л["без назви"],
                     всього - л["з описом"] - л["без назви"], len(ІД.findall(т))))
