# -*- coding: utf-8 -*-
"""Розбір 3/8: де річ їде номером чи сирим id БЕЗ опису (рішення власника: «речі,
які отримує функціональна модель, — завжди з повним описом»).

Рядок ДО — те, що пішло в модель у прогоні власника 25.09 (розклад 4123): скільки
номерів «#N·MM» стоять обʼєктом речі з `назва`, скільки голим номером, скільки в
запиті СИРИХ id крамниць. Рядок ПІСЛЯ — той самий суд, пропущений через теперішні
`вердикт_моделі._номери_в_тексті` (сирий id → номер пулу) і `протокол.вердикт_на_дріт`
(номер → обʼєкт речі, номер у реченні → назва).
Прогін: cd джерела && python3 проби/шлях_пул_опис_у_запитах.py
"""
import json, os, re, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import протокол as ПР, вердикт_моделі as ВМ
ФАЙЛ = os.path.join(os.path.dirname(ТУТ), "аудит", "тести", "власник_2026-09-25",
                    "verdykty-0phxvk-2026-09-25-2012.json")
НОМЕР, ІД = re.compile(r"#\d+·\d\d"), re.compile(r"[а-яїієґ]-\d{4,}@[\w.\-]+")

def з_описом(вузол, л):
    if isinstance(вузол, dict):
        if НОМЕР.fullmatch(str(вузол.get("н") or "")):
            л["з описом" if вузол.get("назва") else "без назви"] += 1
        [з_описом(v, л) for v in вузол.values()]
    elif isinstance(вузол, list):
        [з_описом(v, л) for v in вузол]

def лічба(мітка, тіло):
    т, л = json.dumps(тіло, ensure_ascii=False), {"з описом": 0, "без назви": 0}
    з_описом(тіло, л)
    у = len(НОМЕР.findall(т))
    print("%-38s номерів %3d: обʼєктом з описом %3d, без назви %3d, ГОЛИМ %3d | сирих id %3d"
          % (мітка, у, л["з описом"], л["без назви"], у - л["з описом"] - л["без назви"],
             len(ІД.findall(т))))

def назад(суд):
    """Суд на дроті → обʼєкт коду, з тією самою чисткою сирих id, що й `знахідки_вердикту`."""
    о = []
    for з in суд:
        т = з.get(ПР.ТВІЙ_ОБРАЗ) or {}
        рч = [r if isinstance(r, dict) else {"н": r} for r in (т.get("речі") or [])]
        суд_з = {к: v for к, v in з.items() if к != ПР.ТВІЙ_ОБРАЗ}
        for зн in (суд_з.get("знахідки") or []):
            ном = {ід: tuple(ПР._база_номера((зн.get("речі") or ["#0·00"])[0])[1:].split("·"))
                   for ід in ІД.findall(json.dumps(зн, ensure_ascii=False))}
            ном = {к: (int(v[0]), v[1]) for к, v in ном.items() if len(v) == 2 and v[0].isdigit()}
            зн.update({к: ВМ._номери_в_тексті(v, ном) for к, v in зн.items() if isinstance(v, str)})
        о.append(dict({к: v for к, v in т.items() if к != "речі"}, речі=[r.get("н") for r in рч],
                      описи=рч, **суд_з))
    return {"образи": о}

for пр in json.load(open(ФАЙЛ, encoding="utf-8"))["прогони"]:
    for в in пр["вердикти"]:
        for c in ((в.get("етапи") or {}).get("виклики") or []):
            т = (c.get("запит") or {}).get("текст") or "" if isinstance(c.get("запит"), dict) else ""
            if not т.startswith("{"):
                continue
            д = json.loads(т)
            лічба("рука %s · %-20s ДО" % (в.get("рука"), c.get("крок")), д)
            if д.get(ПР.ВЕРДИКТ_ОБРАЗІВ):
                лічба("%29s ПІСЛЯ" % "", ПР.вердикт_на_дріт(назад(д[ПР.ВЕРДИКТ_ОБРАЗІВ])))
