"""Проба (рядки 2350, 2351). 2350: `palettes.обіцянка_схеми` — нейтральна виміряна річ + срібні сережки, чий
колір знає лише слово металу, в акцентному слоті: «увесь нейтральний» не доведено → знахідок K-COL-03 нема.
2351: `колір_хрома.волосся_неприродне({"C": 40})` — відтінок невідомий → не True. Запуск із джерела/."""
import sys
sys.path.insert(0, "."); import palettes as ПЛ, колір_хрома as КХ                 # noqa: E401,E402
спец = {"_схема": "нейтрали_акцент", "верх": {"роль": "база", "C": [0, 8]},
        "сережки": {"роль": "акцент", "C": [30, 70]}}
верх = dict(id="v", слот="верх", hex="#d8d4cc", назва="v")
сер = dict(id="s", слот="сережки", hex="#c0c0c0", метал="срібло", колір_не_вимір=True, назва="s")
за_ід = {r["id"]: r for r in (верх, сер)}
print("сережки: колір невідомий %s · несе колір %s" % (ПЛ._колір_невідомий(сер), ПЛ._несе_колір(сер)))
з = [x["ярлик"] for x in ПЛ.обіцянка_схеми([верх, сер], спец, за_ід) if x["правило"] == "K-COL-03"]
print("2350 K-COL-03 (очікую —): %s" % (з or "—"))
п = ПЛ.повідомлення_схеми_жінці([верх, сер], спец, за_ід, акцент={})
print("2350 картка (очікую None): %s" % (п and str(п)[:120]))
сер2 = dict(сер, id="s2", hex="#c8102e", метал=None, колір_не_вимір=None)
з2 = [x["ярлик"] for x in ПЛ.обіцянка_схеми([верх, сер2], спец, {"v": верх, "s2": сер2})]
верх3 = dict(верх, id="v3", слот="верх")
з3 = [x["ярлик"] for x in ПЛ.обіцянка_схеми([верх3], {**спец, "верх": {"роль": "акцент", "C": [30, 70]}}, {"v3": верх3})]
print("контроль: червоні сережки — %s; лише нейтральний верх в акценті — %s" % (з2 or "—", з3 or "—"))
print("2351 волосся_неприродне({C:40}) (очікую False): %s · h=10 → %s · h=60 → %s" % (
    КХ.волосся_неприродне({"C": 40}), КХ.волосся_неприродне({"C": 40, "h": 10}), КХ.волосся_неприродне({"C": 40, "h": 60})))
