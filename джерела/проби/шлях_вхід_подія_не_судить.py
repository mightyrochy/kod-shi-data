"""Розбір 1/8 (вхід і сценарій): `подія` — ЄДИНЕ ПОЛЕ, ЩО НЕСЕ ЇЇ СЛОВА, І ЙОГО НЕ ЧИТАЄ НІЩО, ЩО СУДИТЬ.
Визначальні поля сценарію — `сценарій.ВИЗНАЧАЛЬНІ` (нагода, місце, дрес_код, ошатність); `подія`
там не стоїть, тож «похід на концерт» лишається лише рядком для моделі. Друкує перелік
визначальних, `є_сценарій` на самій події, ошатність за нагодою й те, куди `подія` доходить.
Запуск із теки `джерела`: `python3 проби/шлях_вхід_подія_не_судить.py`."""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import сценарій as СЦ, паспорт_нагоди as ПН

print("сценарій.ВИЗНАЧАЛЬНІ = %s — «подія» серед них: %s"
      % (list(СЦ.ВИЗНАЧАЛЬНІ), "подія" in СЦ.ВИЗНАЧАЛЬНІ))
for підпис, п in (("лише подія її словами", {"подія": "похід на концерт"}),
                  ("подія + нагода «щоденне» (прогін власника)", {"подія": "похід на концерт", "нагода": "щоденне"}),
                  ("подія + місце «театр» (той самий концерт ключем)", {"подія": "похід на концерт", "місце": "театр"})):
    с, незн = СЦ.з_показу({}, п)
    смуга = next((р["діапазон"] for г in ("нагоди", "місця") for р in ПН.довідник()[г]
                  if р["ключ"] in (п.get("місце"), п.get("нагода"))), None)
    print("\n%s:" % підпис)
    print("   є_сценарій=%s | сцен: нагода=%s місце=%s ошатність=%s | смуга довідника=%s"
          % (СЦ.є_сценарій(с), с.get("нагода"), с.get("місце"), с.get("ошатність"), смуга))
    print("   випадок моделям: «%s»" % ПН.паспорт_рядком(п))
print("\nдоходить `подія` лише до: `паспорт_рядком` (рядок випадку в пакет рук), `типоваНазваСценарію`"
      " (назва сценарію) і `чогоБракує` (чи можна тиснути «Зібрати образи») — `показ.html:6193`")
print("не доходить до: смуги ошатності, добору пулу, суду — вони читають ВИЗНАЧАЛЬНІ")
print("у паспорті власника 25.09: подія=«похід на концерт», нагода=«щоденне» [3,4] — суд бере [3,4]")
