# -*- coding: utf-8 -*-
"""K-PAL-12 (драматизація м'якої палітри) — умова прийому судить образ.

Корпус (тема-2:1858): «м'яку палітру робити драматичною контрастом світлоти,
фактурою і блиском, А НЕ ХРОМОЮ; лише під statement при chroma < 0» (Lamport 2019,
hint). `palettes.прийоми` умикав прийом рівно за цією умовою — і на тому все
закінчувалось: образ, який драматизується гучним кольором замість світлоти,
жодного слова не діставав.
ПІСЛЯ: коли прийом активний і образ узяв гучний колір (хрома ≥ K-COL-02 `hi_C`)
при малому розмаху світлоти (< 30 L*), правило називає, що важіль узято не той.
Запуск із теки `джерела`: `python3 проби/pal_K-PAL-12.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import pipeline as PL, реєстр_правил as РП

вх, r, кат, спец = ПВ.стенд(гілка=0, намір="statement")
П = спец["палітра_практична"]
акт = {x["прийом"] for x in П["прийоми"] if x["активний"]}
гучно = РП.C["hi_C"]
print("вісь ясності %.2f, намір statement → прийом «драматизація_м_якої» активний: %s"
      % (П["осі"]["позиція"]["chroma"], "драматизація_м_якої" in акт))
гучний = lambda L, C, h, _: not PL._нейтральний_тон(h, C, L) and C >= гучно
# ГУЧНА РІЧ — З КАТАЛОГУ: пул м'якої жінки її законно не містить, а правило
# говорить саме про випадок, коли образ усе ж пішов у гучний колір.
акц = ПВ.з_каталогу(кат, "верх", гучний) or ПВ.з_каталогу(кат, "сукня", гучний)
if not акц or "драматизація_м_якої" not in акт:
    print("ФАКТ · %s — правилу нема про що говорити на цьому вході"
          % ("прийом неактивний" if "драматизація_м_якої" not in акт else "гучної речі в пулі нема"))
    raise SystemExit(0)
L0 = ПВ.lch(кат, акц["id"])[0]
поруч = [ПВ.взяти(r, кат, с, lambda L, C, h, _: abs(L - L0) < 30)
         or ПВ.з_каталогу(кат, с, lambda L, C, h, _: abs(L - L0) < 30)
         for с in ("низ", "взуття", "сумка")]
поруч = [x for x in поруч if x]
if len(поруч) < 2:
    print("ФАКТ · речей у смузі світлоти ±30 L* замало — образу з малим розмахом не скласти")
    raise SystemExit(0)
ід = [x["id"] for x in [акц] + поруч if x]
Ls = [ПВ.lch(кат, x["id"])[0] for x in [акц] + поруч]
print("образ: гучна «%s» (хрома %.0f), розмах світлоти %.0f L*"
      % ((акц["назва"] or "")[:30], ПВ.lch(кат, акц["id"])[1], max(Ls) - min(Ls)))
зн, _ = ПВ.знахідки(вх, ід)
print("ФАКТ · K-PAL-12: %s" % ПВ.рядок(зн, "K-PAL-12"))
z = next((x for x in зн if x.get("правило") == "K-PAL-12"), None)
assert bool(z) == (max(Ls) - min(Ls) < 30), (bool(z), max(Ls) - min(Ls))
if z: print("       ремонт: %s" % z["ремонт"])
