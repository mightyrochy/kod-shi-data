"""Рядок 2530: плитка нагоди в «Оціни мій образ» — чи дає вона смугу ошатності, як на екрані сценарію.
Шлях показу: плитка (не «Інше») → той самий хід плиток мовної моделі без листа (`ходомРозмовиП`, де
`review_tiles`, `chosen` — лише її плитка) → `formality` полем `сценарій_плитки` → `оцінка_образу.
сценарій_оцінки` ставить її смугою сцени (звідки — tiles). Відповідь моделі тут — заглушка (6–8 для свята, 5–7 для побачення); промпт і розбір
— справжні. Запуск із `джерела`: python3 проби/шлях_оцінка_плитка_смуга.py"""
import sys, re, json; sys.path.insert(0, '.')
import оцінка_образу as О, мовний_шар as МШ
exec(open('проби/шлях_оцінка_екран_образ.py', encoding='utf-8').read().split('for назва, екран')[0].split('"""', 2)[2])
T = open('показ.html', encoding='utf-8').read()
ряд = lambda взір: T[:re.search(взір, T).start()].count('\n') + 1
print("показ: плитка → хід плиток (показ.html:%d); її formality → `сценарій_плитки` (показ.html:%d)" % (
      ряд(r"ходомРозмовиП\('', \[\], 'review_tiles'"), ряд(r"\{сценарій_плитки: сценарійПлитки\}")))
def хід(нагода, смуга):
    п = json.loads(МШ.промпт_розмови({"розмова": {"нове": "", "історія": []}, "сценарій": {"нагода": нагода}}))
    в = МШ.прийняти_розмову(json.dumps({"update": {"formality": {"from": смуга[0], "to": смуга[1]}},
                                       "need": "none", "text": "Так."}))["внутрішня"]
    return п["chosen"], ({"formality": в["formality"]} if "formality" in в else None)
def сцена(екран, плитки, ош):
    рр = [dict(р, ошатність=ош) for р in речі]
    с = О.суд(dict(вх, речі=рр, сценарій_оцінки=екран, сценарій_плитки=плитки, крамниця=False))
    зн = sorted({з["правило"] for з in с["суд"]["findings"] if str(з["правило"]).startswith(("K-KOH", "K-OCC"))})
    return с["сцена"].get("ошатність"), с["сцена_звідки"].get("ошатність"), зн
підсумок = {}
for нагода, смуга in (("свято", (6, 8)), ("побачення", (5, 7))):
    chosen, слова = хід(нагода, смуга)
    for коли, сл in (("ДО (плитки ніхто не бачить)", None), ("ПІСЛЯ (хід плиток)", слова)):
        ош, звідки, зн = сцена({"нагода": нагода}, сл, 2)
        підсумок[(нагода, коли[:2])] = зн
        print("  плитка «%s» chosen=%s, речі ошатністю 2 · %-27s смуга: %-7s звідки: %-9s ошатність: %s" % (
              нагода, json.dumps(chosen), коли, ош or "—", звідки or "—", "+".join(зн) or "—"))
assert not any(підсумок[(н, "ДО")] for н in ("свято", "побачення")), "до правки ошатність уже судилась?"
assert all(підсумок[(н, "ПІ")] for н in ("свято", "побачення")), "плитка з ходом плиток не судиться"
assert сцена({"нагода": "свято"}, хід("свято", (6, 8))[1], 6)[2] == [], "ошатні речі на святі — знахідка?"
print("→ плитка без слів тепер має смугу тим самим ходом, що на екрані сценарію; ошатність 2 на святі\n"
      "  й побаченні судиться (K-KOH/K-OCC), ошатні речі — без знахідки. Без мовного шару — як там: без смуги.")
