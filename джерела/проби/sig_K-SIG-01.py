# -*- coding: utf-8 -*-
"""K-SIG-01 (сигнал розкоші не встановлений — заборона СИМЕТРИЧНА) і гейт над
ВЛАСНОЮ мовою коду.

ДО ПРАВКИ: `перевірити_образ` рахує `мовний_гейт` — прогін заборонених формул по
полях ВЛАСНИХ знахідок (суть, чому, ремонт). Докстрінг функції пояснює навіщо:
«заборонена формула найімовірніше з'явиться не у вільному тексті ШІ, а в РЕМОНТІ
наших власних правил — саме там система радить, що робити з тілом». Читав це поле
рівно один споживач — прилад `run_outfit.py`. На шляху `від_моделі`, тобто там, де
знахідки справді їдуть жінці, воно не виходило нікуди, і «промовчало правильно» не
відрізнялось від «ніколи не перевірялось».
ПІСЛЯ: `мовний_гейт_коду` виходить завжди — з лічбою, а не тишею. Проба показує
обидва боки: заборонена формула ловиться (і саме під K-SIG-01), а власні рядки
коду на живому образі чисті."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, language_gate as LG

фрази = ["Ця сумка читається дорого", "У такому взутті ви виглядатимете дешево",
         "Годинник сигналізує статус", "Справить враження заможної людини"]
спіймано = 0
for ф in фрази:
    в = LG.перевірити(ф, режим="блокувати")
    пр = [x["правило"] for x in (в.get("порушення") or [])]
    спіймано += ("K-SIG-01" in пр)
print("заборонених формул статусу перевірено %d · спіймано під K-SIG-01: %d"
      % (len(фрази), спіймано))
assert спіймано == len(фрази), "заборона симетрична: обидва боки однаково безпідставні"
# і протилежний бік — те, що з тієї ж літератури ЛИШАЄТЬСЯ придатним
ок = LG.перевірити("Читається як обраний елемент, а не випадковий", режим="блокувати")
print("«читається як обраний, а не випадковий» →",
      "дозволено" if not (ок.get("порушення") or []) else "ЗАБЛОКОВАНО — помилка")
assert not (ок.get("порушення") or [])

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
ід = [next(c for c in кат if c.get("слот") == сл)["id"]
      for сл in ("сукня", "взуття", "сумка", "прикраси")]
вм = json.loads(B.виклик("від_моделі", json.dumps(
    dict(вх, сценарій=dict(вх["сценарій"], тривалість_год=9), ід=ід), ensure_ascii=False)))
г = вм.get("мовний_гейт_коду") or {}
print("гейт над власною мовою коду на живому образі: чисто=%s, брудних рядків %d"
      % (г.get("чисто"), г.get("брудних")))
assert г, "гейт над власною мовою мусить виходити назовні, а не лишатись у приладі"
assert г["чисто"], "власні рядки коду порушують заборонені формули: %s" % г.get("правила")
