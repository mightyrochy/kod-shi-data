# -*- coding: utf-8 -*-
"""«Лише слід» у мовного гейта: що він робить і що з того бачить споживач.
Прогін: cd джерела && python3 проби/lang_lyshe_slid.py"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import language_gate as МГ, вердикт_моделі as ВМ, знахідка as ЗН
import зведення as ЗВ, gate_reach as ГД, rule_genus as РР, корпус as КР

ТЕКСТИ = [("сезонний вирок", "Ваш сезон — Winter, тому беріть холодні відтінки"),
          ("«прочитають правильно»", "Ця сумка читається дорого — оточення побачить ваш статус"),
          ("чиста фраза", "Пальто шерстяне, довжина нижче коліна")]
for мітка, т in ТЕКСТИ:
    в = МГ.перевірити(т, режим="блокувати")
    ріш = ВМ.мова_рішення(в, спроб=ВМ.МОВНИХ_СПРОБ)
    print("── %s: можна_видавати=%s, порушення=%s" % (мітка, в["можна_видавати"],
          [п["правило"] for п in в["порушення"]] or "—"))
    print("   модель  ← повтор: %s" % bool(ВМ.мова_повтор(в, спроба=1)))
    print("   власник ← лог:    %s" % ((ріш or {}).get("позначка") or "—"))
    print("   жінка   ← рядок:  %s" % ("текст %s, рядка з ID нема"
          % ("з позначкою" if (ріш or {}).get("показувати_текст") else "не показано")
             if ріш else "чистий текст"))
    print("   форма знахідки у вироку: %s" % ([o.get("правило") for _, o in ЗН.усі(в)] or "—"))
print("── межа гейта (його власний докстрінг): ловить ФОРМУЛУ, не намір")
for т in ("Ти зима, тому носи холодні відтінки", "Носи це, щоб тебе сприймали серйозно"):
    print("   %-38s → порушень %d" % (т[:38], МГ.перевірити(т)["порушень"]))

АНТИ = ["K-SIG-01", "R-TYP-04", "R-TYP-05", "R-PSY-02", "R-PP-09"]
ДУБЛІ = [ід for ід in ("R-PC-02", "R-PC-05", "R-PC-08", "R-PP-01", "R-PP-08")]
корп = set(КР.ід())
print("── вердикт зведення для десяти ID (виміряно: слід=так, знахідки нема) ──")
print("   поза корпусом (рядка в зведенні нема): %s"
      % ([ід for ід in АНТИ + ДУБЛІ if ід not in корп] or "—"))
for клас, мітка in (("знахідка", "до "), (None, "після")):
    ряд = {ід: ЗВ.вердикт(клас or ГД.клас_сліду(ід), "так", ["language_gate.py"],
                          [], True, False) for ід in АНТИ}
    for ід in ДУБЛІ:
        ціль = РР.ВИНЯТКИ[ід]["дубль"]
        ряд[ід] = ЗВ.вердикт("знахідка", "так", [], [], False, False, дубль=ціль,
                             вердикт_дубля=(ряд.get(ціль) if ціль in корп else None))
    print("   %s %s" % (мітка, {ід: ряд[ід] for ід in АНТИ + ДУБЛІ if ід in корп}))
