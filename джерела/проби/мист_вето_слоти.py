"""Проба рядка 2961: вето принт спершу зі слотом, потім без — чи лишається слот у `вето_тверде.слоти`."""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import мовний_шар as М
сц = {"id": "walk"}
хід = lambda в, сл, п=None: М.паспорт_з_шару(в, сц, паспорт_досі=п, слова_ходу=сл)["паспорт"]
вужче = {"vetoes": [{"slot": "shoes", "pattern": "print_generic", "quote": "без принта на взутті"}]}
широко = {"vetoes": [{"pattern": "print_generic", "quote": "без принта взагалі"}]}
п1 = хід(вужче, "без принта на взутті")
п2 = хід(широко, "без принта взагалі", п1)
п3 = хід(вужче, "без принта на взутті", п2)
п4 = хід(широко, "без принта взагалі", п3)
for ім, п in (("1 «без принта на взутті»", п1), ("2 «без принта взагалі»", п2),
              ("3 знову «на взутті»", п3), ("4 знову «взагалі»", п4)):
    т = п["вето_тверде"]
    print(ім, "| принти:", т["принти"], "| слоти:", т["слоти"])
# той самий збіг через коментар до образу (`паспорт_з_коментаря`)
к1 = М.паспорт_з_коментаря(вужче, п1)["паспорт"]
к2 = М.паспорт_з_коментаря(широко, к1)["паспорт"]
print("коментар: вужче →", к1["вето_тверде"]["слоти"], "| потім широко →", к2["вето_тверде"]["слоти"])
