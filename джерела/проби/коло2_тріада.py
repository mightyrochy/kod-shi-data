"""КОЛО-2, рядок 1610: чи впізнає тріада взірець власниці «оливковий жакет, блакитна сорочка,
бордова спідниця». Тони — медіани тону речей каталогу з цим словом кольору (п.9: вікно слова —
вжиток крамниць). Якір — кожна з трьох речей (жінка обрала її основою): дві інші мусять лягти в
дві інші дуги тріади (`палітра_схеми.СХЕМИ["тріада"]`). Дві міри: суд K-PAL-03 (дуга + запас 10°,
`суд_від_моделі.схема_образу`) і строга дуга пулу (±15°, без запасу). ДО — +120°/+240° у CIELAB.
Запуск із `джерела`: python3 проби/коло2_тріада.py (потрібен повний каталог)."""
import sys, pathlib, math
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import feed as F; F.каталог_на_диску('каталог_повний.xml')
import фід_каталог as ФК, colorspace as cs, палітра_схеми as PS
кат = ФК._прочитати_каталог('каталог_повний.xml', 0)['каталог']
def мед(слово):
    hs = [cs.lch(tuple(r["lab"]))[2] for r in кат if r.get("колір_назва") == слово and r.get("lab")
          and cs.lch(tuple(r["lab"]))[1] > 8]
    return math.degrees(math.atan2(sum(math.sin(math.radians(h)) for h in hs),
                                   sum(math.cos(math.radians(h)) for h in hs))) % 360, len(hs)
кут = lambda a, b: abs((a - b + 180) % 360 - 180)
ВЗІРЕЦЬ = {с: мед(с) for с in ("оливковий", "блакитний", "бордовий")}
print("взірець:", ", ".join("%s h%.0f (коло %.0f, n=%d)" % (с, h, cs.у_коло_художника(h), n)
                             for с, (h, n) in ВЗІРЕЦЬ.items()))
ДО = lambda h: [(h + 120) % 360, (h + 240) % 360]
ПІСЛЯ = lambda h: [(lo + ((hi - lo) % 360) / 2) % 360 for р, (lo, hi) in PS.СХЕМИ["тріада"]["тон"](h).items()
                   if р != "домінанта"]
ПІВ, ЗАПАС = 15.0, 10.0                 # пів-дуга тріади в СХЕМИ; запас K-PAL-03 у суді
впізнано = {}
for хто, центри in (("ДО", ДО), ("ПІСЛЯ", ПІСЛЯ)):
    for якір, (h, _) in ВЗІРЕЦЬ.items():
        інші = [x for с, (x, _) in ВЗІРЕЦЬ.items() if с != якір]
        ц = центри(h)
        відх = min(max(кут(ц[0], інші[0]), кут(ц[1], інші[1])), max(кут(ц[0], інші[1]), кут(ц[1], інші[0])))
        суд, пул = відх <= ПІВ + ЗАПАС, відх <= ПІВ
        впізнано.setdefault(хто, []).append(суд)
        print("%-5s якір %-9s → центри %3.0f° і %3.0f° · найбільший відхил %4.1f° · суд K-PAL-03 %s · дуга пулу %s"
              % (хто, якір, ц[0], ц[1], відх, "✔" if суд else "✗", "✔" if пул else "✗"))
for хто, v in впізнано.items():
    print("ФАКТ · %s: взірець власниці — тріада для суду з %d із 3 якорів %s" % (хто, sum(v), "✔" if any(v) else "✗"))
