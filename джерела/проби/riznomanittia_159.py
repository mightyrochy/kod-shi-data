ГОЛОВА = 3
for назва, (сц, бажання, акс) in СЦ.items():
    вже, голови, повтори, з_акс, кросівки = set(), {с: set() for с in ("взуття", "верх", "низ")}, 0, 0, set()
    for збір, сід in enumerate((101, 202, 303)):
        d = dict(база, сценарій=сц, випадок=назва, сід=сід, паспорт=dict(бажання=бажання), без_фото=1, вже_були=sorted(вже))
