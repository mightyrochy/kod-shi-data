"""935-ОЧІ: дев'ять названих хиб, відтінки, брак входу й невизначеність слова.
Це звірка збережених вердиктів, не незалежна оцінка нової вибірки очима."""
import sys
sys.path.insert(0, '.')
import colorspace as cs, колір_річ as КР, колір_відношення as КВ, palettes as ПЛ
пари = [('5b6e82', 'a8d5dc', 'ні'), ('5b6e82', 'b4d9de', 'ні'),
        ('7fa6c8', '4dbaca', 'ні'), ('7fa6c8', '36409b', 'так'),
        ('5b6e82', '93dbe1', 'ні'), ('7fa6c8', '095b57', 'ні'),
        ('7fa6c8', '66e0ee', 'ні'), ('759087', '03414b', 'ні'),
        ('5b6e82', '43beb9', 'ні')]
запис = lambda hex: КР.запис_кольору(dict(lab=cs.hx('#' + hex)))
for очі, річ, очікуване in пари:
    x = dict(lab=cs.hx('#' + річ))
    вердикт = КР.у_сім_ї_очей(x, запис(очі))
    print(очі, річ, вердикт, 'очікуване', очікуване)
    assert вердикт == очікуване
for очі in ('5b6e82', '759087', '7fa6c8', '3b2417'):
    assert КР.у_сім_ї_очей(dict(lab=cs.hx('#' + очі)), запис(очі)) == 'так'
assert КР.у_сім_ї_очей(dict(lab=cs.hx('#36409b')), запис('5b6e82')) == 'ні'
assert КР.у_сім_ї_очей(dict(lab=cs.hx('#36409b')), None) == 'невідомо'
assert ПЛ.колір_очей(dict(h=240, C=20)) is None
р = запис('36409b')
вікно = dict(р, C=(13, 58), L=(20, 90), дуга=(190, 300), коло=(210, 286))
с = КВ.сила_сім_ї_очей(вікно, запис('7fa6c8'))
assert с[0] < .5 <= с[1] and КВ.вердикт(с) == 'невідомо'
assert КВ._смуга_сили((20, 20), (-25, 30), 0) == (1, 1)
assert КВ._смуга_сили((20, 40), (-25, 30), 0) == (0, 1)
assert КВ._смуга_сили((40, 50), (-25, 30), 0) == (0, 0)
print('9/9 збережених хиб; двійники, насичений синій до приглушених очей, брак осей і вікно — OK')
