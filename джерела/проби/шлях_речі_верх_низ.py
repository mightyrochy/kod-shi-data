# -*- coding: utf-8 -*-
"""Доповнення до Л-5: її ВЕРХ і НИЗ з фото «займають одне місце» — закріплюється один.

`річ_з_фото.закріпити` рахувало конфлікт ПЕРЕТИНОМ `займає(а) & займає(б)`, а
`займає` несе не лише місце речі, а й місця, які вона СОБОЮ закриває: верх —
{верх, сукня, комплект}, низ — {низ, сукня, комплект}. Перетин непорожній
({сукня, комплект}), тож код читав два її знімки як дві речі на одному місці й
лишав закріпленою лише пізнішу: руки збирали образ з ОДНІЄЮ її річчю.
Правильна умова — той самий слот, або слот однієї серед місць, які закриває інша
(`займають_одне`, так само в Л-6 `оцінка_образу.займають_одне`).
Прогін: cd джерела && python3 проби/шлях_речі_верх_низ.py
"""
import os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import річ_з_фото as Р
ПАРИ = (("верх", "низ", "стоять разом"), ("верх", "сукня", "сукня замінює пару"),
        ("сукня", "низ", "сукня замінює пару"), ("верх", "верх", "той самий слот"),
        ("взуття", "сумка", "стоять разом"), ("низ", "взуття", "стоять разом"))
print("перетин `займає` (стара умова) проти `займають_одне` (нова):")
одне = getattr(Р, "займають_одне", lambda а, б: bool(Р.займає(а) & Р.займає(б)))
for а, б, як_має_бути in ПАРИ:
    print("  %-8s + %-8s | перетин `займає` %-5s | займають_одне %-5s | має бути: %s"
          % (а, б, bool(Р.займає(а) & Р.займає(б)), одне(а, б), як_має_бути))
print()
print("`закріпити` на її двох знімках (порядок — як у паспорті, пізніша перемагає):")
for а, б, як_має_бути in ПАРИ:
    вих = Р.закріпити([dict(ід="ф1", слот=а), dict(ід="ф2", слот=б)])
    скільки = sum(1 for x in вих if x["закріплена"])
    print("  %-8s + %-8s → закріплено %d із 2: %s%s"
          % (а, б, скільки, [(x["ід"], x["слот"], x["закріплена"]) for x in вих],
             "" if (скільки == 2) == (як_має_бути == "стоять разом") else "   ← ВАДА"))
вад = sum(1 for а, б, як in ПАРИ
          if (sum(1 for x in Р.закріпити([dict(ід="ф1", слот=а), dict(ід="ф2", слот=б)])
                  if x["закріплена"]) == 2) != (як == "стоять разом"))
print("ПАР, ДЕ ЗАКРІПЛЕННЯ ХИБНЕ: %d із %d" % (вад, len(ПАРИ)))
