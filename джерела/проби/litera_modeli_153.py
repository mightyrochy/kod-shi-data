# -*- coding: utf-8 -*-
# Рядок 153: після #405 назва giardini стала «Лофери V шкіряні зелені» — артикул
# зняли, самотня літера моделі лишилась, і вона є в СИРОМУ `<name>`, тобто в заяві
# «код не знає», у звіті власника й у тексті, по якому шукають бажання жінки.
# Друкує ФАКТ на СИРОМУ каталозі (`каталог_повний.xml.gz`): лічбу по КРАМНИЦЯХ і
# 40 назв «до → після» для ручного огляду очима (п.10).
import gzip, os, re, sys, collections
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import назва_речі
ТИПОВИЙ = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       os.pardir, "каталог_повний.xml.gz")
ШЛЯХ = sys.argv[1] if len(sys.argv) > 1 else ТИПОВИЙ
сирий = (gzip.open if ШЛЯХ.endswith(".gz") else open)(ШЛЯХ, "rt", encoding="utf-8").read()
# Порядок як у чистці: спершу артикул, тоді літера (за літерою стоїть число, поки
# артикул на місці — «Чоботи Козаки жіночі F 000123»).
чисто = lambda н: назва_речі.зняти_літеру_моделі(назва_речі.зняти_артикул(н))
речі = []
for о in re.finditer(r"<offer\b.*?</offer>", сирий, re.S):
    н = re.search(r"<name>([^<]*)</name>", о.group(0))
    м = re.search(r"<url>https?://(?:www\.)?([^/<]+)", о.group(0))
    if н:
        речі.append((м.group(1) if м else "?", н.group(1)))
пари = [(маг, н, чисто(н)) for маг, н in речі]
рух = [(маг, а, б) for маг, а, б in пари if а != б and назва_речі.зняти_артикул(а) != б]
print("назв у каталозі: %d · літеру моделі знято в %d" % (len(пари), len(рух)))
print("по крамницях: %s" % dict(collections.Counter(м for м, _, _ in рух)))
# САМОТНЯ ВЕЛИКА ЛАТИНСЬКА ЛІТЕРА, ЯКА ЛИШИЛАСЬ, — і чому це правильно.
ОДИН = re.compile(r"(?:(?<=\s)|^)[A-Z](?:(?=\s)|$)")
лишилось = [(м, б) for м, _, б in пари
            if ОДИН.search(назва_речі.зняти_артикул(б).strip())]
print("самотня велика латинська літера ПІСЛЯ правки: %d · %s"
      % (len(лишилось), dict(collections.Counter(м for м, _ in лишилось))))
for м, б in лишилось[:8]:
    print("   лишилась (не код): %s | %s" % (м, б[:70]))
# НАЗВА ПОКАЗУ (те, що бачить ЖІНКА): `почистити` теж знімає літеру, інакше
# `param назва_показу` лишався б із нею — спіймано ручним оглядом (п.10).
без_літери = lambda н: назва_речі.почистити(н)
з_літерою = lambda н: назва_речі.зняти_самоповтор(
    (назва_речі._ВИСЯЧЕ.sub("", назва_речі.звести_регістр(назва_речі.зняти_код(
        назва_речі.зняти_рекламу(назва_речі.розкодувати(н)))).strip(" ,·|-–—"))
     or назва_речі.звести_регістр(назва_речі.зняти_код(назва_речі.зняти_рекламу(
        назва_речі.розкодувати(н)))).strip(" ,·|-–—")))
показ = [м for м, н in речі if з_літерою(н) != без_літери(н)]
print("назва ПОКАЗУ змінилась через літеру: %d · %s"
      % (len(показ), dict(collections.Counter(показ))))
print("\n40 назв «до → після» (ручний огляд очима):")
for маг, а, б in рух[:40]:
    print("  %s\n    → %s" % (а, б))
