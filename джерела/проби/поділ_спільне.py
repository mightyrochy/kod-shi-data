"""Спільний код усіх проб поділу: докстрінг — перший Expr(Constant(str)) у тілі
функції/класу/модуля, тому теж частина AST, і хвиля стандарту (СТАНДАРТ §5 п.17,
118 функцій без докстрінга) зробила б кожен новий докстрінг у поділеному модулі
падінням проби й окремою парою в реєстрі поділу. dump_без_докстрінгів дає
ast.dump копії вузла з прибраними докстрінгами (сам код копії не міняється), щоб
проби порівнювали логіку, а не наявність тексту докстрінга."""
import ast
import os
import copy


def _без_докстрінгу(тіло):
    if тіло and isinstance(тіло[0], ast.Expr) and isinstance(тіло[0].value, ast.Constant) \
            and isinstance(тіло[0].value.value, str):
        return тіло[1:]
    return тіло


def dump_без_докстрінгів(node):
    вузол = copy.deepcopy(node)
    for n in ast.walk(вузол):
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef, ast.Module)):
            n.body = _без_докстрінгу(n.body)
    return ast.dump(вузол)


РЕЄСТР = os.path.join(os.path.dirname(os.path.abspath(__file__)), "поділ_очікувані.d")


def файли_реєстру():
    """Усі файли реєстру поділу, за іменем: тека `поділ_очікувані.d/`, один файл на рядок дошки."""
    return [os.path.join(РЕЄСТР, ім) for ім in sorted(os.listdir(РЕЄСТР)) if ім.endswith(".txt")]


def очікувані(модуль):
    """Множина ключів «новий_модуль::ім'я», свідомо змінених після поділу `модуль`.py.
    Читає ОБ'ЄДНАННЯ всіх файлів теки `поділ_очікувані.d/`: один запис — один рядок
    «<модуль> | <новий_модуль>::<ім'я> | <sha>… [| нота]»; «#» і порожній рядок — не записи.
    Ім'я, свідомо прибране після поділу, пишеться «<модуль> | знесено::<ім'я> | …» (нота каже,
    що стоїть замість нього); проба поділу, яка це вміє, не рахує його загубленим.
    Віддає МНОЖИНУ, тож ні файл, ні порядок рядків, ні повторений ключ на вердикт не впливають —
    саме тому кожен рядок дошки тримає СВІЙ файл і паралельні гілки не конфліктують ніде,
    зокрема на серверному злитті GitHub, яке драйвера `merge=union` не виконує."""
    ключі = set()
    for шлях in файли_реєстру():
        with open(шлях, encoding="utf-8") as ф:
            for рядок in ф:
                р = рядок.strip()
                if not р or р.startswith("#"):
                    continue
                поля = [ч.strip() for ч in р.split("|")]
                if len(поля) < 2:
                    raise ValueError("%s: рядок без полів — %r" % (os.path.basename(шлях), рядок))
                if поля[0] == модуль:
                    ключі.add(поля[1])
    return ключі


def очікувані_і_знесені(модуль):
    """Пара (ОЧІК, знесені) для проби поділу `модуль`.py.

    «знесено::ім'я» у реєстрі — ім'я, свідомо прибране після поділу; нота запису каже,
    що стоїть замість нього. Таке ім'я не «загублене». Із ОЧІК викидаються ВСІ записи
    цього імені, у тому числі чужі пари «новий_модуль::ім'я»: вузла вже нема, тож
    очікувати від нього розбіжності нема кому, і стара пара не має червонити пробу.

    До 27.09.2026 це вміла лише `поділ_pipeline_ast.py` — решта 13 проб рахували
    свідоме знесення загубленим вузлом. Саме тому `поділ_bridge_ast.py` стояла червоною
    на `main` після П-5 (`bridge.порада` знесено, d2729f4a): проба не мала чим це
    записати. Механізм тут один на всі проби.
    """
    ОЧІК = очікувані(модуль)
    знесені = {к.split("::", 1)[1] for к in ОЧІК if к.startswith("знесено::")}
    return {к for к in ОЧІК if к.split("::", 1)[1] not in знесені}, знесені


def загублені_імена(до, де, знесені):
    """Імена, що були у файлі до поділу й не знайшлись у жодному новому модулі.

    Свідомо знесене ім'я (`знесені`) загубленим не рахується. А от знесене ім'я, яке
    ВСЕ ЩЕ живе в коді, — падіння з поміткою «живе знесене»: реєстр і код розійшлись.
    """
    return (sorted(set(до) - set(де) - знесені)
            + sorted("живе знесене: " + і for і in знесені & set(де)))
