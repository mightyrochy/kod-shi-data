"""Друкує різницю між браком контексту, запереченням і заявленим задумом."""
import pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import суд_образу as С, accessory as А, fit as П
import реєстри as РЕ, реєстр_правил as Р
import json, мовний_шар as М, паспорт_нагоди as Н, формальність as Ф
from вхід_правила import нема_входу

if __name__ == "__main__":
    тіло = {"профіль": [("щиколотка", 10, 8), ("литка", 34, 16), ("коліно", 48, 12), ("стегно", 70, 18)]}
    речі = [dict(id="boots", слот="взуття", верх_см=20), dict(id="skirt", слот="низ", низ_см=60)]
    for значення in (None, False, True):
        зн = П.смуга_шкіри(тіло, речі, тон_колготи=значення)
        assert зн and нема_входу(зн[0]) == (значення is None), зн
        if значення is None:
            assert зн[0]["сила_нп"] == 0 and зн[0]["бракує"][0]["field"] == "тон_колготи"
        print("колготи", значення, "→", зн[0]["сила"], зн[0]["сила_нп"])
        колона = А.надточний_збіг([], заявлена_колона=значення)
        assert bool(колона) == (значення is None), колона
        if колона: assert нема_входу(колона[0])
    for контекст in ({}, {"роль": "speaker", "гардероб": []}):
        ч = С.чеклісти([], [], контекст=контекст)
        чужі = [dict(правило="K-KOH-07", сила="soft", сила_нп=0.7),
                dict(правило="K-ACC-07", сила="питання", сила_нп=0, без_входу="інше_поле")]
        після = С.позначити_без_входу(ч, чужі)
        for поле in ("роль", "гардероб"):
            п = next(p for p in після["надлишок"] if p["вхід"] == поле)
            assert п["стан"] == ("пройдено" if поле in контекст else "без входу"), п
        print("Відомість ролі й гардероба не змінює знахідка іншого рішення правила")
    речі = [dict(id=к, назва=РЕ.РЕЄСТРИ[к]["маркери"][0]) for к in ("класика", "gorpcore")]
    for значення in (None, False, True):
        зн, о = РЕ.перевірити(речі, Р.зн, заявлений_злам=значення)
        суд = [з for з in зн if з["правило"] in ("K-REG-01", "K-REG-05")]
        assert bool(суд) == (значення is False), (значення, о, суд)
        print("заявлений злам", значення, "→", [з["правило"] for з in суд])
    р = М.прийняти_розмову(json.dumps(dict(update={"activity": dict(value="bowling", quote="Йду на боулінг")}, text="Записала", need="none")))
    п = М.паспорт_з_шару(р["внутрішня"], {}, слова_ходу=["Йду на боулінг"])["паспорт"]
    с, _ = Н.з_показу({}, п)
    assert с["активність"] == "боулінг" and Ф.сценарій(активність=с["активність"])["практика"]
    print("activity=bowling → боулінг → практичне обмеження взуття")
