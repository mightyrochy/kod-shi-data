"""Рішення менеджера 05.11, «перевір на каталозі»: чи розходяться кадри однієї галереї одноколірного товару понад
розкид виміру. Одноколірний — за знімком платформи (Woo — терм кольору один; Shopify — одне значення опції кольору
чи її нема); запис каталогу — за адресою сторінки; кадри — виміряні галереї (`каталог_кадри`); групи — тим самим
судом, що й спір кольору (`кадри_групи.групи_кадрів`: вікно вжитку слова навколо кадру жнив). Звіт для людей,
продукт його не читає. Аргументи: теки знімків (Woo, Shopify)."""
import collections, gzip, json, sys
from pathlib import Path
КОРІНЬ = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(КОРІНЬ / "джерела"), str(КОРІНЬ / "zhnyvarka")]
import жниварка as ж, shopify_варіанти as ш, складальник as с
from woo_варіанти import норм_адреса, магазин
from кадри_групи import групи_кадрів


def одноколірні(тека):
    """{(домен, норм_адреса сторінки)} одноколірних товарів знімка."""
    вих = set()
    for п in sorted(Path(тека).glob("*.json.gz")):
        домен, тт = п.name[:-8], json.loads(gzip.decompress(п.read_bytes()))
        for т in тт or []:
            if "permalink" in т:
                вв = ж.варіанти_woo(т, "https://" + домен, ж.woo_рецепт(домен))
                адреса = т["permalink"]
            else:
                опції = [(о.get("name") or "").strip() for о in т.get("options") or []]
                вв = ш.варіанти_shopify(т, {"колір": [о for о in опції if ж.re.search(r"кол[іи]р|цвет|colou?r", о, ж.re.I)], "розмір": []})
                адреса = "https://%s/products/%s" % (домен, т.get("handle"))
            if вв and len(вв) == 1 and вв[0]["кольорів_у_товарі"] == 1:
                вих.add((домен, норм_адреса(адреса)))
    return вих


def main():
    _, записи = с.читати_записи()
    км = json.loads(gzip.decompress((КОРІНЬ / "джерела/каталог_кадри.json.gz").read_bytes()))["записи"]
    зб = json.loads(gzip.decompress((КОРІНЬ / "джерела/каталог_збагачення.json.gz").read_bytes()))
    один = set().union(*(одноколірні(т) for т in sys.argv[1:]))
    л, приклади = collections.Counter(), []
    for з in записи:
        домен = магазин(з)
        if (домен, норм_адреса(з.get("адреса"))) not in один:
            continue
        л["записів"] += 1
        ключ = з["ід"] + "@" + домен
        if ключ not in км:
            continue
        г = групи_кадрів(зб.get(ключ), км[ключ])
        виміряних = sum(len(x["кадри"]) for x in г["групи"])     # `вимір_кадру`: придатна поверхня з розкидом
        л["з_вимірами_галереї"] += 1
        л["кадрів_галереї_в_каталозі_кадрів"] += len(км[ключ])
        л["виміряних_кадрів"] += виміряних
        if len(г["групи"]) > 1:
            л["розходяться"] += 1
            поза = sum(len(x["кадри"]) for x in г["групи"][1:])
            л["кадрів_поза_першою_групою"] += поза
            if len(приклади) < 8:
                приклади.append("%s: %s" % (ключ, " | ".join("%s%s×%d" % ("якір " if x["якір"] else "", "/".join(x["слова"]), len(x["кадри"])) for x in г["групи"])))
    print(json.dumps(л, ensure_ascii=False, sort_keys=True))
    print("\n".join(приклади))


if __name__ == "__main__":
    main()
