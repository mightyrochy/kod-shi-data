# -*- coding: utf-8 -*-
"""Рядок 101: стеля 12 питань стояла в КОДІ (`міст_відповіді`), тобто до картки
Й ДО ЗВІТУ. Рішення власника 20.09.2026: «у звіті для мене мають бути вказані
абсолютно всі проблеми і етапи». Проба міряє на 12 сідах стенда, скільки питань
«код не знає» доїжджало до звіту ДО (стеля) і ПІСЛЯ (повний перелік), і на
скількох сідах у ньому видно R-FP-07 «крій прочитано з фото». Друкує факт.

Відповідь про R-FP-07 (і тут, і на живому стенді, 12 сідів × 4 руки): стеля його
НЕ ховала — частка однакова до й після. Коли правило говорить, воно стоїть у
першій дванадцятці; мовчить воно там, де в образі нема речі зі спірним кроєм."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

СТЕЛЯ, R_FP_07 = 12, "крій прочитано з фото"
вх0 = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх0["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх0["гілка"] = 0
до, після, фп_до, фп_після = [], [], 0, 0
for сід in range(1, 13):
    вх = dict(вх0, сід=сід)
    з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    пул = json.loads(з["руки"]["1"]).get("пул") or {}
    речі = [пул[с][0]["н"] for с in ("сукня", "верх", "низ", "взуття", "сумка", "прикраси")
            if пул.get(с)]
    відп = json.dumps(dict(версія="1", образи=[dict(ід="о1", підпис="проба", речі=речі)]),
                      ensure_ascii=False)
    в = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=відп),
                                                     ensure_ascii=False)))
    пит = [str(p.get("суть") or "") for p in (в.get("питання") or [])]
    до.append(min(len(пит), СТЕЛЯ)); після.append(len(пит))
    фп_до += any(R_FP_07 in s for s in пит[:СТЕЛЯ])
    фп_після += any(R_FP_07 in s for s in пит)
    print("сід %2d: у звіті було %2d, стало %2d%s"
          % (сід, до[-1], після[-1], "  ← стеля різала" if після[-1] > СТЕЛЯ else ""))
print("рука 1 на 12 сідах: до %d питань разом (стеля %d), після %d (+%d)"
      % (sum(до), СТЕЛЯ, sum(після), sum(після) - sum(до)))
print("сідів зі стелею: %d/12 · R-FP-07 «%s» у звіті: до %d/12, після %d/12"
      % (sum(1 for a, b in zip(до, після) if b > a), R_FP_07, фп_до, фп_після))
assert sum(після) > sum(до), "стеля мусила різати хвіст — інакше міряти нема чого"
assert фп_після >= фп_до, "знятий зріз не може відібрати питання"
