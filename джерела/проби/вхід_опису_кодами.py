# -*- coding: utf-8 -*-
"""Мірило наряду Е2-вхід-опису-кодами: скільки разів назва речі з крамниці, повний id чи слово крамниці
(`shop`, `shop_color`) іде у вхід моделі опису й перекладача — на живому шляху каталогу.

Живий шлях — той самий, що `тест_живого_шляху.py` (6 прогонів: гілки × наміри, `каталог_brief.xml`); опис
кличеться двічі: як там (без номерів пулу) і як у показі (з номерами `від_моделі.вибір.номери`). Перекладач
текстів картки — `мовний_шар.промпт` з речами тієї самої картки (`речіШаруП`: н, назва, тип, колір, hex);
перекладач повідомлень — `мовний_шар.промпт_повідомлень` із заявою `her_item_stands_in_slot` над речами
картки (`item_ids`). Місце — одне входження назви, id чи ключа крамниці в промпті. Модель не потрібна.

Запуск із `джерела/`: python3 проби/вхід_опису_кодами.py  (ДО — та сама проба на робочому дереві origin/main).
"""
import json
import os
import sys

ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ)
os.chdir(ТУТ)

import тест_живого_шляху as Т  # noqa: E402
import bridge as B  # noqa: E402
import feed as Ф  # noqa: E402
import мовний_шар as МШ  # noqa: E402
import statements as З  # noqa: E402

пійм = []
_виклик = B.виклик


def _обгортка(ім, вх):
    в = _виклик(ім, вх)
    if ім == "опис":
        пійм.append((json.loads(вх), json.loads(в)))
    elif ім == "від_моделі":
        пійм.append(("від_моделі", json.loads(в)))
    return в


B.виклик = _обгортка


def місця(промпт, речі):
    """Входження назв, повних id і ключів крамниці в одному промпті."""
    назви = sum(промпт.count(json.dumps(р["назва"], ensure_ascii=False)[1:-1]) for р in речі if р.get("назва"))
    ід = sum(промпт.count(str(р["id"])) for р in речі)
    крамниця = промпт.count('"shop"') + промпт.count('"shop_color"')
    return назви, ід, крамниця


def main():
    вх_база = json.load(open("стенд_вх.json", encoding="utf-8"))
    вх_база["каталог"] = Ф.каталог_на_диску(Т.КАТАЛОГ)
    import tempfile
    вх_база["кеш_кольорів"] = os.path.join(tempfile.gettempdir(), "кеш_живого_шляху.json")
    if not os.path.exists(вх_база["кеш_кольорів"]):
        json.dump({}, open(вх_база["кеш_кольорів"], "w"))
    підсумок = dict(опис=[0, 0, 0], опис_з_номерами=[0, 0, 0], перекладач=[0, 0, 0], повідомлення=[0, 0, 0])
    прогонів = 0
    for гілка in Т.ГІЛКИ:
        for намір in Т.НАМІРИ:
            пійм.clear()
            Т.прогін(вх_база, гілка, намір)
            прогонів += 1
            вм = [в for к, в in пійм if к == "від_моделі"]
            вх_оп, оп = next((к, в) for к, в in пійм if к != "від_моделі")
            записи = {str(з.get("id")): з for з in Ф.база_прогону(вх_база["каталог"], 0, вх_база["кеш_кольорів"])["каталог"]}
            речі = [dict(р, назва=р.get("назва") or (записи.get(str(р["id"])) or {}).get("назва")) for р in вх_оп["речі"]]
            підсумок["опис"] = [а + б for а, б in zip(підсумок["опис"], місця(оп["промпт"], речі))]
            номери = next(((в.get("вибір") or {}).get("номери") for в in reversed(вм) if (в.get("вибір") or {}).get("номери")), None)
            if not номери:
                номери = {р["id"]: "#%d·%02d" % (к + 1, к + 1) for к, р in enumerate(речі)}
            оп2 = json.loads(_виклик("опис", json.dumps(dict(вх_оп, номери=номери), ensure_ascii=False)))
            підсумок["опис_з_номерами"] = [а + б for а, б in zip(підсумок["опис_з_номерами"], місця(оп2["промпт"], речі))]
            розмітка = [dict(н=1, ключ="опис", текст="A camel trench coat over a white shirt.")]
            шар = [dict(н=номери.get(р["id"]) or str(к + 1), назва=р.get("назва"), тип=р.get("тип") or р.get("item_type"),
                        слот=р.get("слот"), колір=р.get("колір"), hex=р.get("hex"), опис="опис")
                   for к, р in enumerate(речі)]
            підсумок["перекладач"] = [а + б for а, б in zip(підсумок["перекладач"], місця(МШ.промпт(розмітка, шар), речі))]
            заява = З.створити("her_item_stands_in_slot", recipient="woman", item_ids=[р["id"] for р in речі])
            пов = МШ.промпт_повідомлень(МШ.розмітити_повідомлення({"к": {"kind": "card_scheme", "statements": [заява]}}))
            підсумок["повідомлення"] = [а + б for а, б in zip(підсумок["повідомлення"], місця(пов, речі))]
    print("прогонів живого шляху: %d (каталог %s)" % (прогонів, Т.КАТАЛОГ))
    print("вхід моделі             назва  повний_id  shop/shop_color")
    for к, (н, і, ш) in підсумок.items():
        print("  %-22s %5d  %9d  %15d" % (к, н, і, ш))
    print("МІСЦЬ УСЬОГО: %d" % sum(sum(в) for в in підсумок.values()))


if __name__ == "__main__":
    main()
