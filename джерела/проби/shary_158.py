# -*- coding: utf-8 -*-
"""Рядок 158: скільки складених образів мають пару шарів, що «не налізе», і чи код це бачить.
10 образів на сцену — як заглушка стенда (`рв6_стенд.js`), плюс на сцені театру — образ
тестувальниці «Ір» (светр ж-03970@maxa.ua + піджак ж-02168@twice.com.ua). «пар» — образів
із парою за драбиною K-OUT-06 (`outer.драбина_шарів`; на main її нема — тоді детектор
береться з файла гілки: DRABYNA=<шлях до верхнє_стан.py>); «гейт» — з них у вердикті є
K-OUT-06 регістру «гейт»; «вибір» — чи `вибір_з_json` бере образ із парою.
Запуск: cd джерела && python3 проби/shary_158.py"""
import json, sys, os, importlib.util
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, outer, стенд_знімок as СЗ
_дш = getattr(outer, "драбина_шарів", None)
if _дш is None:
    _сп = importlib.util.spec_from_file_location("дш", os.environ["DRABYNA"]); _м = importlib.util.module_from_spec(_сп)
    _сп.loader.exec_module(_м); _дш = _м.драбина_шарів
СЦЕНИ = dict(СЗ.СЦЕНАРІЇ, **{"театр·концерт·14°C": dict(нагода="театр", місце="театр", година=19, темп_c=14),
                             "парк·собаки·18°C·вітер": dict(нагода="прогулянка", місце="парк", година=10, темп_c=18, вітер=8)})
ТРЕТІ = ("верхній_шар", "прикраси", "пояс", "шарф", "головний_убір", "сережки", "намисто", "кольє", "браслет", "брошка")
for назва, сц in СЦЕНИ.items():
    вх = dict(json.load(open("стенд_вх.json")), сценарій=сц, випадок=назва)
    к = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["кандидати"]
    кат = {x["id"]: x for x in B.каталог_останнього_пакета()}
    в_ = lambda с, i: к[с][i % len(к[с])]["id"] if к.get(с) else None
    тр = [с for с in ТРЕТІ if к.get(с)]
    образи = [[x for x in ([в_("сукня", i)] if (к.get("сукня") and i % 2) else [в_("верх", i), в_("низ", i)])
               + [в_("взуття", i), в_("сумка", i), в_(тр[i % len(тр)], i) if тр else None] if x] for i in range(1, 11)]
    if назва.startswith("театр"):
        образи[0] = ["ж-03970@maxa.ua", "ж-02168@twice.com.ua"] + [в_(с, 0) for с in ("низ", "взуття", "сумка", "прикраси")]
    пари = [bool([z for z in _дш([dict(кат[і]) for і in о if і in кат]) if z.get("сила") != "питання"]) for о in образи]
    в = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=образи), ensure_ascii=False)))
    гейт = sum(1 for о, п in zip((в.get("вердикт") or {}).get("образи") or [], пари) if п and any(
        z.get("правило") == "K-OUT-06" and z.get("регістр") == "гейт" for z in о.get("знахідки") or []))
    обр = next((і for і, п in enumerate(пари) if п), None)
    вибір = "—" if обр is None else json.loads(B.виклик("від_моделі", json.dumps(dict(вх, відповідь="ВИБІР_V1",
        вибір_над=в["вибір_над"], текст_моделі=json.dumps({"версія": "1", "обрано": "о%d" % (обр + 1)})), ensure_ascii=False)))["вибір"]
    print("%-24s пар %d/10 · гейт %d · вибір образу з парою: %s" % (назва, sum(пари), гейт,
          вибір if вибір == "—" else ("бере" if set(вибір["ід"]) == set(образи[обр])
          else "не бере" + (" (K-OUT-06)" if "K-OUT-06" in str(вибір["чому_відмова"]) else " (інший гейт)"))))
