"""Записані профілі: оцінка портрета, фізичний вимір і ручний ввід мають різне походження."""
import json, pathlib, sys
К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(К))
import colorspace as cs, face_features as О, міст_вхід as М


def main():
    """Звіряє джерело кожної риси, довіру, донорський шлях і оновлення кешу."""
    помилки = []
    база = json.loads((К / "стенд_вх.json").read_text("utf8"))
    профілі = sorted((К.parent / "аудит/проби/жінки").glob("*.json"))
    assert профілі, "нема записаних профілів"
    for шлях in профілі:
        ж = json.loads(шлях.read_text("utf8"))
        вх = dict(база, шкіра=ж["skin"], волосся=ж["hair"] * 2, очі=ж["eyes"], очі_кільце="#111111")
        вх.pop("source", None)
        F = М.features(вх)[0]; запис = О.ознаки(F, "uncontrolled")
        помилки += [шлях.stem + ": походження"] * int(запис["контраст"]["джерело"] != "оцінка моделі")
        помилки += [шлях.stem + ": довіра камери"] * int(any(запис["надійність"].values()))
        помилки += [шлях.stem + ": додані риси"] * int(any(
            р["джерело"] != "оцінка моделі" for р in запис["риси"].values()))
        помилки += [шлях.stem + ": from_photo"] * int(F["_meta"]["from_photo"])
        помилки += [шлях.stem + ": дріт"] * int(О.для_моделі(запис)["eyes"]["source"] != "model_hex")
        донор = М.збірка(вх, донорський=True)[0]
        помилки += [шлях.stem + ": донор"] * int(О.ознаки(донор)["протокол"] != "model_hex")
        вимір = О.ознаки(М.features(dict(вх, source="spectro"))[0])
        помилки += [шлях.stem + ": спектро"] * int(вимір["очі"]["довіра"] != 1.0)
        F["_meta"]["protocol"] = "spectro"
        помилки += [шлях.stem + ": кеш"] * int(О.ознаки(F) is запис)
    ручний = cs.features(cs.hx("#deb295"), cs.hx("#523321"), cs.hx("#735632"))
    помилки += ["ручний ввід"] * int(О.ознаки(ручний)["очі"]["джерело"] != "її слово")
    явний = О.ознаки(ручний, "model_hex")
    помилки += ["явне джерело"] * int(явний["очі"]["довіра"] or явний["очі"]["джерело"] != "оцінка моделі")
    print("профілів:", len(профілі), "· порушень походження:", len(помилки), помилки)
    return bool(помилки)


if __name__ == "__main__":
    sys.exit(main())
