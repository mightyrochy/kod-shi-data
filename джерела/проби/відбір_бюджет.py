"""Міряє залежність ремонту від порядку складу за незмінних оцінок судді й ввімкненого бюджету."""
import json, pathlib, random, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import повнота_образу as П

слоти = ['верх', 'низ', 'взуття', 'сумка', 'верхній_шар', 'шарф', 'головний_убір', 'пояс', 'прикраса']
основа = [f'z{i}' for i in range(len(слоти))]
кандидати = {с: [dict(id=f'a{i}{j}', слот=с) for j in range(6)] for i, с in enumerate(слоти)}
словник = {r['id']: r for пул in кандидати.values() for r in пул}
словник.update({і: dict(id=і, слот=с) for і, с in zip(основа, слоти)})


def суд(склади):
    """Лише a05 прибирає гейт; зняття лишає діру. Фікстура, без моделі."""
    return [dict(ід='о1', речі=с, структура=dict(ок=len(с) == 9, блокери=[] if len(с) == 9 else [dict(код='неповний')]),
                 знахідки=[] if 'a05' in с else [dict(правило='K-KOH-05', регістр='гейт', речі=[])]) for с in склади]


def головна():
    """30 перестановок одного складу: ремонт без `a05` чи відмінний від першого — вада."""
    склади = []
    for сід in range(30):
        склад = list(основа); random.Random(сід).shuffle(склад)
        вирок = dict(ід='о1', речі=склад, структура=dict(ок=True, блокери=[]),
                     знахідки=[dict(правило='K-KOH-05', регістр='гейт', речі=[])])
        ід, _, звіт = П._ремонт_гейтів(склад, {}, вирок, кандидати, dict(словник), {}, суд)
        склади.append((sorted(ід or []), звіт['відкинуто_варіантів']))
    print(json.dumps(dict(перестановок=30, без_ремонту=sum(not с for с, _ in склади),
                          відмінних=sum(с != склади[0][0] for с, _ in склади),
                          бюджет_відкинув=склади[0][1]), ensure_ascii=False))


головна()
