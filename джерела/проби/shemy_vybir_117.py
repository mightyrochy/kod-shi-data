# -*- coding: utf-8 -*-
"""Рядок 117: чи може жінка ОБРАТИ будь-яку схему і чи доїжджає вибір до пулу.
Профіль стенда. (а) `bridge.палітри` для КОЖНОГО наміру дає шість схем — жодна не
прихована. (б) У рідших нота непорожня і без «відкривається / замкнено / не цього
разу». (в) Обрана рідша доходить до пакета САМЕ ТАКОЮ під conventional: вона є в
розвилці пакета, і вікна, з яких будується пул, — її, не «тональної». До (попередня
правка рядка 117): 4 пропоновані + 2 «замкнені», некликабельні, індексом не
адресовані. Запуск із теки `джерела`: `python3 проби/shemy_vybir_117.py`."""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge as B, palette as P
from міст_вхід import _збірка, _якір, _нормалізувати_вхід, _індекс_гілки
from міст_основи import _пакет
ЗАБОРОНЕНІ, СЛОТИ = ("відкривається", "замкнен", "не цього разу"), ["верх", "низ", "взуття", "сумка"]
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
розміри, брак, категоричні = set(), [], []
for намір in ("conventional", "comfort_first", "context_optimal", "statement", "editorial"):
    r = json.loads(B.палітри(json.dumps(dict(вх, намір=намір), ensure_ascii=False)))
    рідші = [г for г in r["гілки"] if г["рідший"]]
    розміри.add(len(r["гілки"]))
    брак += [(намір, г["схема"]) for г in рідші if not (г.get("нота") or "").strip()]
    категоричні += [(намір, г["схема"]) for г in r["гілки"]      # по ВСІХ нотах, не лише рідших
                    if any(з in (г.get("нота") or "").lower() for з in ЗАБОРОНЕНІ)]
    print("%-16s схем %d · радить код %d · рідших %d: %s" % (намір, len(r["гілки"]),
          r["радить_код"], len(рідші), "; ".join(г["нота"] for г in рідші) or "—"))
d = _нормалізувати_вхід(dict(вх, намір="conventional", схема="тріада"))
F, T, зріст, kw = _збірка(d)
п = _пакет(F, T, зріст, kw, _якір(d), "conventional", None, None, None, явні=("тріада",))
розв = п["палітри"]["розвилка"]
і = _індекс_гілки(розв, None, "тріада")
вік = lambda с: {(q.get("слот"), q.get("h_from"), q.get("h_to"))
                 for q in P.запит_у_фід(P.специфікація(F, с, СЛОТИ, intent="conventional"))}
т, тон = вік(розв[і]["схема"]), вік("тональна")
print("ВИБІР «тріада» під conventional: розвилка пакета %s · індекс %s · пул за «%s» · "
      "вікон тріади %d, тональної %d, спільних %d"
      % ([г["схема"] for г in розв], і, розв[і]["схема"], len(т), len(тон), len(т & тон)))
print("ПІДСУМОК: схем %s · рідших без ноти %d · категоричних нот %d" % (sorted(розміри), len(брак), len(категоричні)))
assert розміри == {6} and not брак and not категоричні, (sorted(розміри), брак, категоричні)
assert розв[і]["схема"] == "тріада" and т != тон, "вибір не доїхав: %s" % розв[і]["схема"]
print("ВСІ ТРИ ЗВІРКИ ПРОЙДЕНО")
