"""Звіряє вхід відбору кандидатів оцінки на стендовому профілі.
Запуск з кореня: python3 джерела/проби/проба_кандидати_оцінки.py"""
import json
import os
from pathlib import Path
import sys
import tempfile


def перевірити():
    """На нагоді й без неї зберігає пакет, записи за слотами й причину."""
    джерела = Path(__file__).resolve().parents[1]
    os.chdir(джерела)
    sys.path.insert(0, str(джерела))
    from міст_вхід import збірка
    from міст_основи import пакет_гілки
    from міст_пакет import кандидати_оцінки_кроками
    from оцінка_образу import _каталог_без_пулу_кроками, _крамниця
    from реєстр_правил import ТИПОВИЙ_НАМІР
    from фід_каталог import каталог_на_диску
    from фід_розбір import ганяти

    профіль = json.loads((джерела / "стенд_вх.json").read_text(encoding="utf-8"))
    профіль.pop("випадок", None)
    каталог = каталог_на_диску(str(джерела / "каталог_brief.xml"))
    слоти = ("сукня", "верх", "низ")
    with tempfile.TemporaryDirectory() as тека:
        вхід = dict(профіль, каталог=каталог, кеш_кольорів=str(Path(тека) / "кольори.json"))
        нагода = {к: профіль["сценарій"][к] for к in ("нагода", "місце", "дрес_код", "смуга_погоди")}
        for сцен, пул in (({}, False), (нагода, True)):
            дані = dict(вхід, сценарій=сцен)
            F, T, зріст, kw = збірка(дані)
            п, гілка, _, _ = пакет_гілки(дані, F, T, зріст, kw, None, ТИПОВИЙ_НАМІР)
            новий = ганяти(кандидати_оцінки_кроками(дані, F, T, п, гілка, слоти, _каталог_без_пулу_кроками))
            assert новий[2] is пул and any(новий[0].values()), (новий[1], новий[2])
            assert новий == _крамниця(вхід, F, T, сцен, слоти), "вихід відбору змінився"


if __name__ == "__main__":
    перевірити()
