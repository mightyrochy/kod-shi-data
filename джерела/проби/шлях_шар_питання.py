"""М-1, розбір 8/8: ХТО ВІДПОВІДАЄ НА ЇЇ ПИТАННЯ ПРО ОБРАЗ НА ШЛЯХУ МОВНОГО ШАРУ І ЩО ВІН БАЧИТЬ.
Шар увімкнений типово (модель шару = модель продукту). Друкує, кому `розмоваШаромП` віддає
питання про образ і про застосунок, чи їдуть моделі, що відповідає, фото її речей, і які входи
образу стоять у її промпті (питання, речі, вердикт коду, які фото до яких речей, випадок).
Та сама проба на main і на гілці. Запуск із `джерела`: python3 проби/шлях_шар_питання.py"""
import sys, os, re, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
T = open("показ.html", encoding="utf-8").read()
тіло = lambda ім: (re.search(r"async function %s\(.*?\n\}\n" % ім, T, re.S) or re.search("$", T)).group(0)
розмова = тіло("розмоваШаромП")
хто = lambda про: ("стилісткаП" if "стилісткаП" in розмова and про != "app" else "помічникП")
for про in ("look", "app"):
    print("питання question_about=%-4s → %s" % (про, хто(про) if "question_about" in розмова else "помічникП (теми не читає)"))
відповідач = тіло(хто("look"))
фото = bool(re.search(r"модельП\(\s*[^,()]+,\s*фото\b", відповідач))
print("модель, що відповідає на питання про образ, дістає фото її речей: %s" % ("так, до стелі моста" if фото else "ні"))
спідниця = dict(ід="її-ф1", фото="ф1", назва="мініспідниця зі зміїним принтом", слот="низ", колір="хакі",
                ошатність=6, чия="моя", вердикт=dict(рядок="Личить: колір у твоїй палітрі."))
try:
    import міст_стилістка as С
    промпт = json.loads(С.стилістка(dict(питання="чи підійде ця спідниця на концерт?", речі=[спідниця],
                                         випадок="похід на концерт, театр", фото_речей=["ф1"])))["промпт"]
    д = json.loads(промпт)
    входи = dict(питання=bool(д.get("question")), речі=len(д.get("items") or []),
                 вердикт_коду=sum(1 for р in д.get("items") or [] if р.get("вердикт_коду")),
                 фото_до_речей=len(д.get("photos") or []), випадок=bool(д.get("case")))
except ImportError:
    промпт = тіло("помічникП")
    входи = dict(питання=True, речі=0, вердикт_коду=0, фото_до_речей=0, випадок=False)
print("входи образу в промпті того, хто відповідає: %s" % json.dumps(входи, ensure_ascii=False))
print("довідка про застосунок (ШІ_ДОВІДКА) у цьому промпті: %s" % ("ШІ_ДОВІДКА" in промпт))
