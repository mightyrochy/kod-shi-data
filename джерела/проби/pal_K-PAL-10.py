"""K-PAL-10 (принт) — канал повернувся, і його половина працює чесно.

Корпус (тема-2:1856): «принт придатний, якщо його домінанта в палітрі і
внутрішній контраст ≈ контраст людини». Функцію «принт проти палітри» знесено
нарядом Н-V16-040 («нуль викликів; питання про домінанту принту не ставить
ніхто»), і корпус записав «code: not implemented» з умовою: «якщо канал з'явиться —
писати наново, не відкопувати».
КАНАЛ З'ЯВИВСЯ 16.09: кожна річ пулу несе `колір`/`hex`, тобто домінанту свого
кольору система тепер має — той самий представник, яким її судять скрізь. Написано
наново як знахідку вердикту. ДРУГОЇ ПОЛОВИНИ НЕМА І ЦЕ СКАЗАНО В ПОЛІ `ламається`:
внутрішнього контрасту принту фід не міряє.
Запуск із теки `джерела`: `python3 проби/pal_K-PAL-10.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import pipeline as PL

вх, r, кат, спец = ПВ.стенд(гілка=0, намір="statement")
П = спец["палітра_практична"]
принт_поза = lambda L, C, h, з: (str(з.get("візерунок") or "").lower() not in ("", "solid", "однотонний")
                                 and not PL._нейтральний_тон(h, C, L)
                                 and not PL._у_вікнах(П["вікна"], L, C, h))
річ = next((x for с in ("сукня", "верх", "низ") for x in [ПВ.взяти(r, кат, с, принт_поза)] if x), None)
if not річ:
    print("ФАКТ · у пулі нема принта, чия домінанта поза палітрою — судити нема що"); raise SystemExit(0)
решта = [ПВ.взяти(r, кат, с, lambda *a: True) for с in ("низ", "взуття", "сумка")]
ід = [x["id"] for x in [річ] + решта if x][:4]
print("принт: %s · візерунок «%s» · домінанта L%.0f C%.0f h%.0f"
      % ((річ["назва"] or "")[:36], кат[річ["id"]].get("візерунок"), *ПВ.lch(кат, річ["id"])))
зн, _ = ПВ.знахідки(вх, ід)
print("ФАКТ · K-PAL-10: %s" % ПВ.рядок(зн, "K-PAL-10"))
z = next((x for x in зн if x.get("правило") == "K-PAL-10"), None)
assert z and z["сила"] == "default" and z["сила_нп"] == 0.5, z
print("       ремонт: %s" % z["ремонт"])
