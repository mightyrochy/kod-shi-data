"""Рядок 2812: пояснення картки руки 1 зникало, на його місці — «… — без пояснення словами». Дві форми
відповіді з живого прогону пачки 5, яких розбір не читав, і повтор їх не лагодив (той самий промпт —
та сама відповідь): П1 — шар на шість текстів картки дав один об'єкт вхідної форми {"н": 1, "текст"};
К1 — стилістка загорнула опис у {"answer": {…}} двічі поспіль. Друкує, що розбір читає з кожної.
Збій мережі на виклику рядків картки (Д1, `HTTP 599`) і написи за кнопкою — у тест_показу.js, розділ 1д-1.
Запуск із `джерела`: python3 проби/пояснення_картки_2812.py"""
import sys, json, warnings; sys.path.insert(0, '.'); warnings.simplefilter('ignore')
import мовний_шар as МШ, протокол as П, розбір_відповідей as РВ
EN = "Your base is a sleeveless black dress with a fitted bodice that flares at the waist into a peplum, " * 2
розмітка = [dict(н=1, ключ="опис", текст=EN)] + [
    dict(н=н, ключ=к, текст="The sheer black dress looks dramatic enough.") for н, к in
    [(2, "як_носити.0"), (3, "свідомі.0"), (4, "свідомі.1"), (5, "свідомі.2"), (6, "свідомі.3")]]
УК = ("Твоя основа — це безрукавне чорне плаття з приталеним верхом, який розширюється на талії в пеплум, "
      "що лежить над спідницею-трапецією довжиною до коліна, а зверху — довге чорне пальто.")
в = МШ.прийняти(розмітка, '```json\n{\n  "н": 1,\n  "текст": "%s"\n}\n```' % УК)
print("П1 шар, один {н, текст}: опис прочитано — %s; без відповіді %d з 6 (%s); нотатки %s" % (
    в["тексти"]["опис"] == УК, len(в["без_відповіді"]), в["причина"], в["нотатки"]))
опис = {"answer": {"version": "1", "text": "You are wearing a satiny two-piece suit in a soft peach hue.",
                   "how_to_wear": ["Keep the high slit of the skirt as your main draw."]}}
р = РВ.опис_відповідь_з_json(json.dumps(опис))
print("К1 опис у {answer: …}: текст є — %s; повтор просить — %s; нормалізовано %s" % (
    bool(р["текст"]), "повторний_виклик" in р, р["нормалізовано"]))
р2 = РВ.опис_відповідь_з_json(json.dumps(опис["answer"]))
print("той самий опис без обгортки: текст є — %s; нормалізовано %s" % (bool(р2["текст"]), р2["нормалізовано"]))
сх = П.розбір_за_схемою(json.dumps({"answer": "DESCRIPTION_V1"}), "ОПИС_ВІДПОВІДЬ_V1")[2]["нормалізовано"]
print("«answer» з рядком, а не об'єктом, не знімається:", П.ОБГОРТКУ_ЗНЯТО not in сх)
