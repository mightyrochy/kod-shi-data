# -*- coding: utf-8 -*-
"""каталог_сусіди_заглушка.py — ПРОГІН РОЗБОРУ З СУСІДАМИ ПРОТИ ЗАГЛУШКИ МОДЕЛІ (наряд 5.4-С).

ЩО ПЕРЕВІРЯЄ (без моделі; речі — справжні, з каталогу на диску): `каталог_розбір_прогін.прогін(..., сусіди=...)`
  1. сусіди не йдуть у повний розбір: викликів повного розбору = речей − сусідів;
  2. файл сусіда має ЗАПИТ свого запиту й відповідь представника, а колір — з короткого виклику;
  3. кольорових викликів: «значення» — на унікальне значення, «річ» — на річ;
  4. повторний запуск тієї самої теки не кличе модель (докат за іменем файла і промптом);
  5. без `сусіди` кожна річ іде повним розбором, як доти;
  6. представник упав → його сусіди йдуть повним розбором у тому самому запуску;
  7. `зібрати` читає файли сусідів проти їхнього тексту: колір сусіда лишається, коли цитата є в його картці.
Кінець: «OK», код 0; інакше AssertionError.
"""
import collections
import json
import os
import sys
import tempfile
import warnings

warnings.filterwarnings("ignore")
ТУТ = os.path.dirname(os.path.abspath(__file__))
ДЖЕРЕЛА = os.path.dirname(ТУТ)
if ДЖЕРЕЛА not in sys.path:
    sys.path.insert(0, ДЖЕРЕЛА)

import фід_каталог as ФК                      # noqa: E402
import фід_розбір as ФР                       # noqa: E402
import каталог_розбір as КР                   # noqa: E402
import каталог_розбір_прогін as ПР            # noqa: E402
import каталог_розбір_сусіди as С             # noqa: E402


def _порожня(в):
    """Скелет → відповідь «нічого не сказано»: пара {quote:"", value:"unknown"}, список [], решта рекурсивно."""
    if isinstance(в, dict):
        if set(в) == {КР.ЦИТАТА, КР.ЗНАЧЕННЯ}:
            return {КР.ЦИТАТА: "", КР.ЗНАЧЕННЯ: "unknown"}
        return {к: _порожня(п) for к, п in в.items()}
    return [] if isinstance(в, list) else в


def _вибрати(офери, груп=6, скільки=3):
    """Кілька груп сусідів по `скільки` речей (з полем кольору) + дві одинаки: реальні речі каталогу."""
    за_ключем = collections.defaultdict(list)
    for o in офери:
        ключ, колір = С.розбити(o)
        if колір:
            за_ключем[(o.get("магазин"), ключ)].append(o)
    групи = [г for г in за_ключем.values() if len({tuple(sorted(С.розбити(o)[1].items())) for o in г}) >= скільки]
    групи = sorted(групи, key=lambda г: (-len(г), г[0]["id"]))[:груп]
    речі = [o for г in групи for o in г[:скільки]]
    одинаки = [г[0] for г in sorted(за_ключем.values(), key=lambda г: (len(г), г[0]["id"])) if len(г) == 1][:2]
    return речі + одинаки, групи


def головна():
    офери, _ = ФР.читати_yml(ФК.каталог_на_диску(), показ=False)
    речі, групи = _вибрати(офери)
    assert len(групи) >= 3, "у каталозі на диску нема груп сусідів для проби"
    викликів = collections.Counter()
    падіння = set()

    def заглушка(промпт, ід_моделі, сід=None, схема=True, годинник=None, повтор=None, стадія="річ",
                 макс_токенів=None, ім_схеми=None):
        дані = json.loads(промпт)
        if стадія == "колір":
            викликів["колір"] += 1
            колір = дані["params"]
            значення = next(iter(колір.values()))
            return json.dumps({КР.КОДИ: "color_main=blue=%s" % значення}, ensure_ascii=False), 0.1
        викликів["повний"] += 1
        # Представник: колір з першого поля кольору його ж картки.
        o = next(x for x in речі if x["назва"] in промпт)
        if o["id"] in падіння:
            raise ConnectionError("заглушка: сервер не відповів")
        відп = {КР.КОДИ: "item_type=unknown", КР.ОСОБЛИВОСТІ: "item=plain item"}
        колір = С.розбити(o)[1]
        if колір:
            відп[КР.КОДИ] += ";color_main=red=%s" % next(iter(колір.values()))
        return json.dumps(відп, ensure_ascii=False), 0.1

    ПР.модель = заглушка
    читати, ПР.ФР.читати_yml = ПР.ФР.читати_yml, lambda *a, **к: (речі, None)
    try:
        # 5. без сусідів: усе повним розбором
        з_ = tempfile.mkdtemp()
        ПР.прогін("заглушка", куди=з_, усі=True, паралельно=1)
        assert викликів["повний"] == len(речі) and not викликів["колір"], dict(викликів)
        повних_без = викликів["повний"]

        for режим in С.РЕЖИМИ:
            викликів.clear()
            з_ = tempfile.mkdtemp()
            ПР.прогін("заглушка", куди=з_, усі=True, паралельно=2, сусіди=режим)
            мірка = json.load(open(os.path.join(з_, "прогін.json"), encoding="utf-8"))
            сусідів = [р for р in мірка["речі"] if р.get("сусід_від")]
            assert len(сусідів) == len(речі) - len(групи) - 2, (len(сусідів), len(речі), len(групи))
            assert викликів["повний"] == повних_без - len(сусідів), dict(викликів)
            унікальних = {(С.колір_ключ(o, режим)) for o in речі if С.розбити(o)[1]}
            викликів_кольору = викликів["колір"]
            assert викликів_кольору <= len(унікальних), (dict(викликів), len(унікальних))
            for р in сусідів:
                текст = open(os.path.join(з_, р["файл"]), encoding="utf-8").read()
                запит, _, відп = текст.partition("\n\n── ВІДПОВІДЬ\n")
                o = next(x for x in речі if x["id"] == р["id"])
                assert запит == "── ЗАПИТ\n" + json.dumps(КР.промпт(o), ensure_ascii=False)
                пункт = next(п for п in json.loads(відп)[КР.КОДИ].split(";")
                              if п.startswith("color_main="))
                assert пункт.partition("=")[2].partition("=")[2] in С.розбити(o)[1].values()
            розбір = json.load(open(ПР.зібрати(з_), encoding="utf-8"))
            for р in сусідів:
                assert розбір[р["id"]]["color_main"] != KR_UNKNOWN(), р["id"]
            # 4. докат: модель не кличеться
            викликів.clear()
            ПР.прогін("заглушка", куди=з_, усі=True, паралельно=2, сусіди=режим)
            assert not викликів, dict(викликів)
            print("режим %-8s: сусідів %d · повних викликів %d · кольорових %d · унікальних ключів %d"
                  % (режим, len(сусідів), повних_без - len(сусідів), викликів_кольору, len(унікальних)))

        # 6. представник упав → сусіди повним розбором
        викликів.clear()
        група = групи[0][:3]
        падіння.add(група[0]["id"])
        з_ = tempfile.mkdtemp()
        ПР.прогін("заглушка", куди=з_, усі=True, паралельно=1, сусіди="значення")
        мірка = json.load(open(os.path.join(з_, "прогін.json"), encoding="utf-8"))
        ід = {р["id"]: р for р in мірка["речі"]}
        assert ід[група[0]["id"]]["впало"] and not ід[група[1]["id"]].get("сусід_від"), "сусід не пішов повним"
    finally:
        ПР.ФР.читати_yml = читати
    print("OK")


def KR_UNKNOWN():
    return КР.UNKNOWN


if __name__ == "__main__":
    головна()
