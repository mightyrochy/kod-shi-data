# -*- coding: utf-8 -*-
"""R-COL-16 (вісь речі проти людини — b*; ключ носія — ОЧІ, не ITA) — діє чи ні, пробою.
Корпус (тема-2:841, T2·hint): 77 % обрали вищий b* до темнішого обличчя; §6.1 (тема-2:1712) і
K-COND-02 знімають ключ «ITA шкіри»: вибір іде за ОЧИМА (Perrett 2023). Друкує: (1) частку
хроматичних речей приобличчевих слотів каталогу, яку бік b* ПОНИЖУЄ, для обох боків («a rule
that admits 85 % of the space is not a rule»); (2) стенд як є (очі #759087, b* 1.6 у смузі —
без входу, P7 чекліста); (3) пул руки 1 під темними (#5a3a1e) і світло-синіми (#7fa8d8) очима;
(4) знахідку суду на кольоровій речі біля обличчя з протилежного боку.
Запуск із теки `джерела`: `python3 проби/col_R-COL-16.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ, palette as P, колір_образу as КО, colorspace as cs
БЛИЗЬКІ = {с for с, v in КО.SLOT_NEAR_FALLBACK.items() if v >= КО.NEAR_МІН}
вх, r, кат, спец = ПВ.стенд(гілка=0)
хром = [c for c in кат.values() if c.get("lab") and c["слот"] in БЛИЗЬКІ and КО.нейтраль(tuple(c["lab"])) is None]; боки = [P.бік_b_речі(c["lab"]) for c in хром]
print("каталог: хроматичних речей у приобличчевих слотах %d · теплий бік b* %d · холодний %d · смуга %d"
      % (len(хром), боки.count(1), боки.count(-1), боки.count(0)))
for бік, ім in ((1, "теплий"), (-1, "холодний")):
    ч = 100.0 * боки.count(-бік) / max(1, len(хром))
    print("   очі на %-8s боці → понижує %5.1f %% простору слотів — %s" % (ім, ч, "правило" if ч >= 15 else "НЕ правило (<15 %)"))
    assert ч >= 15.0, ч
бб = спец.get("бік_b") or {}
print("стенд як є: очі %s b* %.1f · вхід %s · ITA шкіри %.0f (%s) — %s"
      % (вх["очі"], бб.get("b_очей"), бб.get("вхід"), бб.get("ITA_шкіри"), бб.get("ITA_смуга"), бб.get("чому")))
assert not бб.get("вхід")
for hex_очей in ("#5a3a1e", "#7fa8d8"):
    вх2, r2, кат2, спец2 = ПВ.стенд(гілка=0, очі=hex_очей)
    бб = спец2["бік_b"]; _, запити = __import__("bridge").спец_останнього_пакета()
    з_боком = sum(1 for q in запити if q.get("b_бік"))
    пул = [(с, кат2[x["id"]]) for с, v in (r2.get("кандидати") or {}).items() if с in БЛИЗЬКІ
           for x in v if (кат2.get(x["id"]) or {}).get("lab") and КО.нейтраль(tuple(кат2[x["id"]]["lab"])) is None]
    print("очі %s b* %.1f → бік %+d · рядків із b_бік %d/%d · пул %d · хроматичних біля обличчя %d: на боці очей %d, проти %d"
          % (hex_очей, бб["b_очей"], бб["бік"], з_боком, len(запити), r2.get("пул_речей") or 0, len(пул),
             sum(1 for _, c in пул if P.бік_b_речі(c["lab"]) == бб["бік"]), sum(1 for _, c in пул if P.бік_b_речі(c["lab"]) == -бб["бік"])))
    assert бб["вхід"] and з_боком > 0
річ = ПВ.з_каталогу(кат2, "верх", lambda L, C, h, з: КО.нейтраль(tuple(з["lab"])) is None and P.бік_b_речі(з["lab"]) == -бб["бік"])
ід = [річ["id"]] + [x["id"] for с in ("низ", "взуття", "сумка") for x in (r2["кандидати"].get(с) or [])[:1]]
зн, _ = ПВ.знахідки(вх2, ід)
print("ФАКТ · верх «%s» b* %.1f проти очей b* %.1f: R-COL-16 %s" % (річ["назва"][:30], річ["lab"][2], бб["b_очей"], ПВ.рядок(зн, "R-COL-16")))
z = next((x for x in зн if x.get("правило") == "R-COL-16"), None); assert z and z["сила"] == "hint" and z["регістр"] == "репліка" and not z.get("блокує"), z
