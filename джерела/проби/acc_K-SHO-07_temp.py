# -*- coding: utf-8 -*-
"""K-SHO-07 (виріз взуття) дістав градуси: при −5 °C зі щільними колготами вісь вимкнена.

ДО: `видимість_краю(речі, темп_c)` брала градуси в сигнатуру й НЕ ЧИТАЛА їх (таблиця
прогалин PR #182, §4 п.13) — `_нога_гола` дивилась лише на ТИП низу, тож −5 °C і +25 °C
давали той самий вердикт. ПІСЛЯ: свідок один — `аксесуари_погода.покриття_ноги` (смуга
den зі `смуга_ніг`, той самий, яким судить K-HOS-01). «ДО» не з пам'яті: параметр не
читався, тож виклик БЕЗ градусів відтворює старий вихід рівно."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, accessory as АК
вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"], вх["гілка"] = Ф.каталог_на_диску("каталог_повний.xml"), 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
пара = next(c for c in кат if c.get("слот") == "взуття" and c.get("виріз_стопи") == "низький")
низ = next(c for c in кат if c.get("слот") in ("низ", "сукня")
           and (c.get("довжина_рівень") or c.get("довжина")) in АК.ДОВЖИНИ_ГОЛОЇ_НОГИ)
колготи = dict(слот="колготи", назва="колготки щільні", den=100, id="проба-колготи")
речі = [dict(низ), dict(пара), колготи]
print("пара «%s» (виріз %s) · низ «%s» (%s) · колготки %d DEN"
      % (пара["назва"][:34], пара["виріз_стопи"], низ["назва"][:28],
         низ.get("довжина_рівень") or низ.get("довжина"), колготи["den"]))  # профіль стенда


def рядок(мітка, зн):
    if not зн:
        print("   %-26s МОВЧИТЬ" % мітка); return None
    з = зн[0]
    print("   %-26s %s %.2f · %s" % (мітка, з["сила"], з["сила_нп"], з["суть"][:58]))
    print("   %-26s %s" % ("", (з.get("чому") or "")[:96]))
    return з

до, х = рядок("ДО (градуси не читались)", АК.видимість_краю(речі)), \
        рядок("ПІСЛЯ −5 °C", АК.видимість_краю(речі, темп_c=-5))
т = рядок("ПІСЛЯ +25 °C", АК.видимість_краю(речі, темп_c=25))
assert до and х and т, "вісь не має зникати з виходу — вона мусить СКАЗАТИ, що вимкнена"
assert х["сила_нп"] < до["сила_нп"], "щільні колготки при −5 °C мусять знижувати силу"
assert (т["сила"], т["сила_нп"]) == (до["сила"], до["сила_нп"]), "+25 °C не міняє нічого"
