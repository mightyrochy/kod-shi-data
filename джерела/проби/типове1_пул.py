# -*- coding: utf-8 -*-
"""ТИПОВЕ-1 (дошка 1406–1408, 1410): чи ріжуть пул і вмикають «день/вечір» поля форми, яких вона не
називала (11:00, +18 °C, місце плитки — `сценарій.типові_поля`), і чи знімає смуга ошатності верхній шар.
Живий міст `запити` на `стенд_вх` + повний каталог. Друкує по сцені: босоніжок/сандалій/еспадрилій
у пулі, тренчів і пальт у верхньому шарі, `day_outing`/`evening_outing` у пакеті руки 1, `day` пакета.
Запуск із теки `джерела`: python3 проби/типове1_пул.py  (≈2 хв)"""
import sys, os, json, collections
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge as B, feed as Ф
КАТ, База = Ф.каталог_на_диску("каталог_повний.xml"), json.load(open("стенд_вх.json", encoding="utf-8"))
ТИП = ["година", "темп_c", "місце"]
ВЕС = dict(нагода="весілля_гість", місце="весілля_вечірнє", година=11, темп_c=18, типові_поля=ТИП)
СЦЕНИ = {
    "весілля плиткою, форма типова": (ВЕС, dict(ошатність=[6, 8], місце="весілля_вечірнє", година=11, темп_c=18,
                                                 джерело_полів={k: "типове_форми" for k in ТИП})),
    "весілля, модель почула «вдень»": (ВЕС, dict(ошатність=[6, 8], місце="весілля_денне", година=11, темп_c=18,
                                                  джерело_полів={"місце": "розмова", "година": "типове_форми",
                                                                 "темп_c": "типове_форми"})),
    "корпоратив без години, +18 її": (dict(нагода="свято", година=11, темп_c=18, типові_поля=["година"]),
                                       dict(ошатність=[7, 8], темп_c=18, джерело_полів={"година": "типове_форми"})),
    "дощ, кав'ярня [3,4], +12 її": (dict(нагода="щоденне", місце="кафе", година=11, темп_c=12, опади="дощ",
                                          типові_поля=["година"]),
                                     dict(ошатність=[3, 4], темп_c=12, опади="дощ", місце="кафе",
                                          джерело_полів={"година": "типове_форми"})),
}
ВІДКРИТЕ = ("босоніжки", "сандалі", "еспадрильї")
for назва, (сц, пасп) in СЦЕНИ.items():
    вх = dict(База, каталог=КАТ, сценарій=сц, паспорт=пасп, випадок=назва)
    r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    взуття = collections.Counter(x.get("тип") for x in r["кандидати"].get("взуття") or [])
    шар = collections.Counter(x.get("тип") for x in r["кандидати"].get("верхній_шар") or [])
    п1 = json.loads(r["руки"]["1"])
    правила = json.dumps(п1.get("style_rules"), ensure_ascii=False)
    print("%-34s відкрите взуття %2d (лофери %d) · тренч %d, пальто %d · day_outing %s, evening_outing %s · day %s"
          % (назва, sum(взуття[т] for т in ВІДКРИТЕ), взуття["лофери"], шар["тренч"], шар["пальто"],
             "day_outing" in правила, "evening_outing" in правила, json.dumps(п1.get("day"), ensure_ascii=False)))
    зн = [з["values"] for з in (r.get("ноти_слотів") or {}).get("верхній_шар") or [] if "occasion" in з["code"]]
    print("    верхній шар за смугою нагоди:", json.dumps(зн, ensure_ascii=False) if зн else "не різався")
