# -*- coding: utf-8 -*-
"""K-PAL-11 (метал) — від сліду до вікна добору.

Корпус (тема-2:1857): «тепла → золото, холодна → срібло, нейтральна → обидва;
самозвіт золото/срібло переважає фото». Доти прийом лишав слід і казав слово в
брифі, а ДОБІР фурнітури про метал не знав нічого. Дві течі, обидві зміряні:
  · `bridge._пакет_каталогу` не передавав `самозвіт` у `palette.специфікація` —
    вікна каталогу будувались БЕЗ відповідей жінки, і на самозвіті «срібло»
    палітра пулу лишалась «обидва»: сам прийом («самозвіт переважає фото») у
    доборі не діяв;
  · під метал не було жодного рядка запиту — золота фурнітура входила лише
    фолбеком «жодна річ слота не влучила у вікна».
ПІСЛЯ: `palettes.рядки_у_фід` кладе золотий і срібний рядки в `СЛОТИ_МЕТАЛУ` під КОЖНУ палітру
(рядок 257, 01.10.2026: «усе можливе доступне людині»). K-PAL-11 симетричне (рішення менеджера 09.11, 14414):
метал палітри — ранг 2, протилежний — ранг 3 і `менш_ходове` (золото під холодною — `jewellery_gold_less_usual_for_cool`,
срібло під теплою — `jewellery_silver_less_usual_for_warm`), нейтральній — обидва ранг 2.
Рядок металу бере річ за тоном коду матеріалу (`palettes.метал_речі`, `feed.влучає_метал`),
а не за кольором: вікна кольору металу нема (14314, крок 30 кореня Річ-колір-межі).
Запуск із теки `джерела`: `python3 проби/pal_K-PAL-11.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вимір as В
import palettes as PAL, feed as Ф


def прогін(мітка, **вх):
    к, кат, спец, зап = В.пул_стенда(гілка=0, **вх)
    П = спец["палітра_практична"]
    рядки = [q for q in зап if q.get("метал")]
    крізь = {"золото": set(), "срібло": set()}
    for слот, пул in к.items():
        for x in пул:
            п = кат.get(x.get("id")) or {}
            for q in рядки:
                if q["слот"] == слот and Ф.влучає_метал(п, q):
                    крізь[q["метал"]].add(x["id"])
    у_пулі = {м: sum(1 for с, пул in к.items() if с in PAL.СЛОТИ_МЕТАЛУ for x in пул
                     if PAL.метал_речі(кат.get(x["id"]) or {}) == м) for м in крізь}
    print("%-22s метал палітри «%s» · рядків металу %d (золотих %d, менш ходових %d) · крізь них золото %d, срібло %d · "
          "у пулі прикрас золото %d, срібло %d" % (мітка, П["метал"], len(рядки),
          sum(1 for q in рядки if q["метал"] == "золото"), sum(1 for q in рядки if q.get("менш_ходове")),
          len(крізь["золото"]), len(крізь["срібло"]), у_пулі["золото"], у_пулі["срібло"]))
    # Ранги — зі справної руки: `запити` моста збирає й пакет руки 2 (`поломки._рядок_протилежного_металу`), і
    # «останній пакет» буває саме ним; рядки тієї самої специфікації дає та сама функція продукту.
    ранги = sorted({(q["метал"], q.get("ранг_риси"), bool(q.get("менш_ходове")))
                    for q in PAL.рядки_у_фід(спец) if q.get("метал")})
    print("%-22s рядки металу справної руки (метал, ранг, менш ходове): %s" % ("", ранги))
    return П["метал"], len(рядки), len(крізь["золото"]), len(крізь["срібло"]), ранги


м1, р1, з1, с1, г1 = прогін("фото, вісь утримано:")
м2, р2, з2, с2, г2 = прогін("самозвіт «срібло»:", самозвіт={"метал": "срібло"})
м3, р3, з3, с3, г3 = прогін("самозвіт «золото»:", самозвіт={"метал": "золото"})
print("ФАКТ · рядків металу %d на «%s» і %d на «%s»; золото крізь них %d проти %d, срібло %d проти %d"
      % (р1, м1, р2, м2, з1, з2, с1, с2))
assert м1 == "обидва" and м2 == "срібло" and м3 == "золото", (м1, м2, м3)
# K-PAL-11 симетричне (14414): рідший метал — ранг 3 і мітка, метал палітри й обидва під нейтральною — ранг 2
assert г1 == [("золото", 2, False), ("срібло", 2, False)], г1
assert г2 == [("золото", 3, True), ("срібло", 2, False)], г2
assert г3 == [("золото", 2, False), ("срібло", 3, True)], г3
assert р1 and р2, (р1, р2)       # золото й срібло доступні кожній палітрі (п.9)
assert з1 and з2 and с1 and с2, (з1, з2, с1, с2)
каблучка = dict(слот="каблучка", метал="срібло")
print("срібна каблучка: %s · латунна каблучка: %s · срібло в слоті «верх»: %s · обруч зі сріблом: %s"
      % (PAL.метал_речі(каблучка), PAL.метал_речі(dict(каблучка, метал="латунь")),
         PAL.метал_речі(dict(слот="верх", метал="срібло")), PAL.метал_речі(dict(слот="прикраси", тип="обруч", метал="срібло"))))
assert PAL.метал_речі(каблучка) == "срібло" and PAL.метал_речі(dict(каблучка, метал="латунь")) == "золото"
assert PAL.метал_речі(dict(слот="верх", метал="срібло")) is None
assert PAL.метал_речі(dict(слот="прикраси", тип="обруч", метал="срібло")) is None
