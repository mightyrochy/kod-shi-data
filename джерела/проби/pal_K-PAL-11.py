# -*- coding: utf-8 -*-
"""K-PAL-11 (метал) — від сліду до вікна добору.

Корпус (тема-2:1857): «тепла → золото, холодна → срібло, нейтральна → обидва;
самозвіт золото/срібло переважає фото». Доти прийом лишав слід і казав слово в
брифі, а ДОБІР фурнітури про метал не знав нічого. Дві течі, обидві зміряні:
  · `bridge._пакет_каталогу` не передавав `самозвіт` у `palette.специфікація` —
    вікна каталогу будувались БЕЗ відповідей жінки, і на самозвіті «срібло»
    палітра пулу лишалась «обидва»: сам прийом («самозвіт переважає фото») у
    доборі не діяв;
  · під метал не було жодного рядка запиту — золота фурнітура входила лише
    фолбеком «жодна річ слота не влучила у вікна».
ПІСЛЯ: `palettes.рядки_у_фід` кладе золотий рядок у `СЛОТИ_МЕТАЛУ` і лише під
метал палітри; срібло рядка не потребує (ахромат — його вже несе нейтральний
рядок); `feed.описує_річ` вимагає, щоб представник речі читався тим самим металом.
Запуск із теки `джерела`: `python3 проби/pal_K-PAL-11.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вимір as В
import palettes as PAL, feed as Ф


def прогін(мітка, **вх):
    к, кат, спец, зап = В.пул_стенда(гілка=0, **вх)
    П = спец["палітра_практична"]
    рядки = [q for q in зап if q.get("метал")]
    крізь_метал = set()
    for слот, пул in к.items():
        for x in пул:
            п = кат.get(x.get("id")) or {}
            if not п.get("lab"): continue
            for q in рядки:
                if q["слот"] != слот or not Ф.описує_річ(п["lab"], q): continue
                ч = Ф.частка_вікна(п["вікно"], q) if п.get("вікно") else (1.0 if Ф.підходить(п["lab"], q) else 0.0)
                if ч > 0: крізь_метал.add(x["id"]); break
    фолбек = [(с, x["назва"]) for с, пул in к.items() if с in PAL.СЛОТИ_МЕТАЛУ
              for x in пул if x.get("id") not in крізь_метал
              and PAL.метал_речі((кат.get(x["id"]) or {}).get("lab") or (0, 0, 0), с) == "золото"]
    print("%-22s метал палітри «%s» · золотих рядків у фіді %d · фурнітури крізь них %d"
          % (мітка, П["метал"], len(рядки), len(крізь_метал)))
    if фолбек:
        print("%-22s золоте повз рядки (гарантія слота — вона сама каже, що на палітру "
              "не спирається): %s" % ("", "; ".join("%s: %s" % (с, н[:34]) for с, н in фолбек[:2])))
    return П["метал"], len(рядки), len(крізь_метал)


м1, р1, ч1 = прогін("фото, вісь утримано:")
м2, р2, ч2 = прогін("самозвіт «срібло»:", самозвіт={"метал": "срібло"})
print("ФАКТ · рядок металу питає золота %d раз на «%s» і %d на «%s»; "
      "фурнітури, що входить саме ним: %d проти %d" % (р1, м1, р2, м2, ч1, ч2))
assert м1 == "обидва" and м2 == "срібло", (м1, м2)
assert р1 and not р2, (р1, р2)
assert ч1 and not ч2, (ч1, ч2)
print("срібло (L*75 C*0) у слоті «каблучка»: %s · у слоті «верх»: %s"
      % (PAL.метал_речі((75.0, 0.0, 0.0), "каблучка"), PAL.метал_речі((75.0, 0.0, 0.0), "верх")))
assert PAL.метал_речі((75.0, 0.0, 0.0), "каблучка") == "срібло"
assert PAL.метал_речі((75.0, 0.0, 0.0), "верх") is None
