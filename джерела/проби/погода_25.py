# -*- coding: utf-8 -*-
"""Крок 2.5 (поняття.md §г): 5 словників опадів, реєстр порогів погоди і рішення на каталозі
(кожна річ × погодні умови на межах 2 °C, 25/26 °C та вітру 6/8/10 м/с) ДО і ПІСЛЯ.
Запуск із `джерела`: python3 проби/погода_25.py"""
import sys, os, re
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import feed, сценарій as СЦ, profile as ПР, протокол as ПТ, паспорт_нагоди as ПН, внутрішня_мова as ВМ
import outfit as O, аксесуари_погода as АП, суд_погода as СП, пакет_моделі as ПМ, суд_від_моделі as СВМ

кат = feed._прочитати_каталог(feed.каталог_на_диску("каталог_повний.xml"))
взуття = [р for р in кат if р.get("слот") == "взуття"]
акс = [р for р in кат if р.get("слот") in ("головний_убір", "шарф", "рукавички", "сумка")]
кльош = [р for р in кат if O.крій_речі(р) in O.ЛЕТКІ_КРОЇ]
опади_js = re.findall(r"\['([^']+)','[^']+','[^']+'\]", re.search(r"const ОПАДИ=\[(.*?)\];", open("показ.html", encoding="utf-8").read()).group(1))
контр = ПР.ПОГОДА_КОНТРАКТ["опади"]["значення"]
вип = ПТ.ВИПАДОК["опади"]["значення"]
print("опади ВМ=%s · канон=%s" % (tuple(ВМ.ТАБЛИЦЯ["precipitation"].values()), СЦ.ОПАДИ_КАНОН))
print("опади profile=%s (усі в каноні: %s) · протокол=%s · показ=%s (усі в каноні: %s)" % (
    контр, all(СЦ.канон_опади(x) == x for x in контр), вип, опади_js, all(x in СЦ.ОПАДИ_КАНОН for x in опади_js)))
рег = getattr(СЦ, "РЕЄСТР_ПОГОДИ", СП.РЕЄСТР_ПОРИ)
print("реєстр порогів (%d): %s" % (len(рег), {k: v["val"] for k, v in рег.items()}))
for t in (1.0, 2.0, 3.0):
    k06 = sum(z["правило"] == "K-WEA-06" for z in АП.сезон_і_погода(взуття, темп_c=t))
    k08 = sum(z["правило"] == "K-WEA-08" for z in АП.сезон_і_погода(акс, темп_c=t))
    сіль = СЦ.сіль_на_дорозі(None, t, "сніг")[0]
    відсів = sum(bool(ПМ.непридатна_для_непогоди(р, {"опади": "мокрий_сніг", "темп_c": t})) for р in кат)
    мороз_суд = t < СП.МОРОЗ_ДО_C
    print("межа 2°C при %+.1f°C: мороз_суд=%-5s K-WEA-06(взуття)=%-4d K-WEA-08(акс)=%-4d сіль=%-5s відсів_замші=%d" % (t, мороз_суд, k06, k08, сіль, відсів))
for t in (25.0, 26.0):
    зима_пул = sum(ПМ._не_по_порі(р, t) == "winter_item_off_temperature" for р in кат)
    зима_акс = sum(z["правило"] == "K-WEA-08" for z in АП.сезон_і_погода(акс, темп_c=t))
    третя_м = bool(СВМ.структура_образу_заяви([{"id": "в", "слот": "верх"}, {"id": "н", "слот": "низ"}, {"id": "вз", "слот": "взуття"}], ("верх", "низ", "взуття", "верхній_шар"), {"темп_c": t})[1])
    print("межа спеки при %+.1f°C: відсів_зимового=%-4d K-WEA-08(зимові_акс)=%-4d K-CRA-01_м'яко(спека)=%s" % (t, зима_пул, зима_акс, третя_м))
for w in (5, 6, 8, 10):
    день_w = bool(СЦ.день_кодами({"вітер": w}).get("wind_ms"))
    шар_w = w >= getattr(СЦ, "ВІТЕР_ПОМІТНИЙ", 6.0)
    кльош_w = len(кльош) if any(z["правило"] == "K-WEA-01" and "кльош" in z["суть"] for z in СП.погода(O.елементи(кльош[:1], стан="надворі"), темп_c=14, вітер=w, стан="надворі", речі=кльош[:1])) else 0
    відсів_w = sum(bool(ПМ.непридатна_для_непогоди(р, {"опади": "дощ", "темп_c": 14, "вітер": w})) for р in кат)
    print("вітер %2d м/с: день=%-5s шар=%-5s K-WEA-01(кльош)=%-4d сильна_непогода(відсів_замші)=%d" % (w, день_w, шар_w, кльош_w, відсів_w))
