"""Рядок 58 дошки: усі АХРОМАТИЧНІ клітинки ҐРАТКИ ОСНОВ (`bridge._ґратка_основ`,
ключ містить «·нейтраль·») підписані словом світлоти («сірий»/«білий»/«чорний»/
«графіт»…), а не словом металевого блиску (`verify.МЕТАЛИ`: «срібний», «золотий»)
— клітинка не річ, фактури в неї нема (K-PAL-11, `palettes.СРІБЛО`/`ЗОЛОТО`
лишаються оцінкою фурнітури, а не підписом чипа). До правки: L*68 C*0 підписана
«срібний». Запуск із теки `джерела`: `python3 проби/sriblo_58.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import bridge as B, verify as V

осн, порядок = B._ґратка_основ()
метал = [(k, осн[k][1]) for k in порядок if "·нейтраль·" in k and осн[k][1] in V.МЕТАЛИ]

print("клітинок ґратки: %d · ахроматичних: %d · підписано словом металу: %d %s"
      % (len(порядок), sum(1 for k in порядок if "·нейтраль·" in k), len(метал), метал or ""))

assert not метал, "ахроматична клітинка підписана словом металу: %s" % метал
print("норма: жодна ахроматична клітинка не підписана «%s»" % "/".join(sorted(V.МЕТАЛИ)))
