# Рядок 1412: сукня без уточнення діставала смугу 3–9 — суд нагоди над головною річчю мовчав.
# Тепер смуга — бал фото ± 1; без бала — «без входу» з полем `формальність_фото` (п.4).
import sys, os, collections
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import feed, фід_каталог as ФК, формальність as ФН, суд_чеклісти as ЧК
кат = ФК._прочитати_каталог(feed.каталог_на_диску("каталог_повний.xml"), 0)["каталог"]
с = [r for r in кат if r.get("тип") == "сукня_без_уточнення"]
шир = collections.Counter((lambda i: None if i[0] is None else int(i[1] - i[0]))(ФН.інтервал_формальності(r)) for r in с)
print("суконь без уточнення %d · ширина смуги %s" % (len(с), dict(sorted(шир.items(), key=str))))
впало = sum(n for w, n in шир.items() if w is not None and w >= 6)
# K-KOH-05 / K-KOH-07 на ювілеї 5–7: казуальна сукня (бал 4) + човники — доти тиша
сцен = {"діапазон": (5, 7), "risk_posture": "neutral"}
сук = {"річ": "с1", "слот": "сукня", "тип": "сукня_без_уточнення", "формальність_фото": 4}
чов = {"річ": "в1", "слот": "взуття", "тип": "човники"}
сум = {"річ": "б1", "слот": "сумка", "тип": "клатч", "формальність": 6}
зн = ФН.формальність_образу([сук, чов, сум], сцен)
print("ювілей 5–7, сукня бал 4: інтервал %s · знахідки %s" % (ФН.інтервал_формальності(сук), [z["правило"] for z in зн]))
впало += 0 if ФН.інтервал_формальності(сук) == (3.0, 5.0) else 1
# без бала: шар мовчить, але пункт 5 чекліста — «без входу» з названим полем
без = dict(сук, формальність_фото=None)
зн = ФН.формальність_образу([без, чов, сум], сцен)
п5 = next(p for p in ЧК.чеклісти(зн, [без, чов, сум])["надлишок"] if p["пункт"] == 5)
print("без бала: інтервал %s · пункт 5 «%s» · бракує: %s" % (ФН.інтервал_формальності(без), п5["стан"], (п5.get("бракує") or "")[:70]))
впало += 0 if п5["стан"] == "без входу" and "формальність_фото" in (п5.get("бракує") or "") else 1
print("ВПАЛО %d" % впало)
