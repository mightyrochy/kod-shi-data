"""Пул лише з інтервалу дає заміну після справжнього переважування образу."""
import json
import sys
from unittest.mock import patch
sys.path.insert(0, ".")
import оцінка_образу as О, річ_з_фото as Р, palettes as П, колір_річ as К


def головна():
    """Перевірити повний суд п'яти речей; ізолювати лише отримання пулу та вітрини."""
    F, T, d = О.профіль(json.load(open("стенд_вх.json", encoding="utf-8")))
    сцен, _ = О._сцена(dict(нагода="робота", місце="офіс", темп_c=18), d)
    слоти = [("верх", "blouse"), ("низ", "trousers"), ("верхній_шар", "blazer"), ("взуття", "dress_shoes"), ("сумка", "tote")]
    речі = [dict(ід="ф" + str(i), слот=с, вид=вид, колір="чорний" if i == 0 else "сірий",
                вимір=dict(lab=(5 if i == 0 else 60, 0, 0), hex="#111111" if i == 0 else "#777777"))
            for i, (с, вид) in enumerate(слоти)]
    кат = [Р.запис_каталогу(dict(р, закріплена=True)) for р in речі]
    assert all(з.get("тип") for з in кат)
    о0 = О._ваги_образу([з["id"] for з in кат], кат, F, T, сцен, None)
    палітра = П.палітра_практична(F); L = sum(палітра["вікна"]["L"]) / 2
    нова = dict(кат[1], id="інтервал-крамниці", колір_тип="інтервал", lab=None, colors=[], власна=False, закріплена=False,
                колір_не_вимір=dict(свідок="shop_word", вікно=(L - 1, L + 1, 0, 1, None)))
    assert К.точка_кольору(нова) is None and Р.членство_вікна(нова, палітра)[0] == "так"
    with patch.object(О, "_крамниця", return_value=({"низ": [нова]}, "проба", True, {})), \
         patch.object(О, "_покажчики_вітрини_кроками", return_value=iter(())), \
         patch.object(О, "вітрина", return_value={}):
        г = О.зміни_кроками({}, F, T, сцен, речі, [р["ід"] for р in речі], [], о0, палітра)
        try:
            while True: next(г)
        except StopIteration as кінець:
            зміни, звіт = кінець.value
    print("Справжній суд: до", о0["сума_сил"], "спроб", len(звіт["спроби"]), "замін", len(зміни), зміни)
    assert len(зміни) == 1 and зміни[0]["нова"] == нова["id"] and зміни[0]["дельта"] < 0
    assert "K-COL-01" in зміни[0]["знято"] and not зміни[0]["додано"]


if __name__ == "__main__":
    головна()
