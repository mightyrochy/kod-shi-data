"""R-CHEV-08: невідоме місце не стає «поза зоною»; суд читає видимість елемента.
Запуск: cd джерела && python проби/е3_місце_увага.py [SHA_ДО]. Код 1 — порушено інваріант."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import регістр_уваги as Р, місце_речі as М
if len(sys.argv) > 1:
    import subprocess, types
    Р = types.ModuleType("регістр_уваги_до")
    exec(compile(subprocess.check_output(["git", "show", sys.argv[1] + ":джерела/регістр_уваги.py"]), "регістр_уваги_до", "exec"), Р.__dict__)
вади = 0
for назва, річ, чекано in (
    ("без речі", None, None),
    ("місце невідоме", dict(id="р", слот="верх"), None),
    ("інша відкрита зона", dict(id="р", слот="верх", відкрита_зона="руки"), None),
    ("відкриває живіт", dict(id="р", слот="верх", відкрита_зона="живіт"), True),
):
    факт = Р.на_мету("верх", річ, зони_мети=["живіт"])
    print(назва, "→", факт, "очікується", чекано)
    вади += факт is not чекано
річ = dict(id="р", слот="верх", lab=[50., 80., 0.])
ранг = Р.ранг_уваги(річ, "експресія", зони_мети=["живіт"])
print("невідоме місце: ранг експресії", ранг, "очікується 0")
вади += ранг != 0
тиха = dict(річ, lab=[30., 1., 0.])
for назва, р, видно, мета, зони, чекано in (
    ("під шаром невідомо", dict(річ, відкрита_зона="живіт"), None, "звично", ["живіт"], 0),
    ("під шаром не видно", річ, 0., "приховати", [], 0),
    ("видно гучну річ", річ, 1., "приховати", [], 1),
    ("видно відкритий живіт", dict(річ, відкрита_зона="живіт"), 1., "звично", ["живіт"], 2),
    ("невідоме місце тихої", тиха, 1., "експресія", ["живіт"], 0),
    ("експресія без зони", тиха, 1., "експресія", [], 1),
):
    запис = dict(М.записати(р), видно=видно, видно_джерело="невідомо" if видно is None else "стилістка")
    е = dict(р, річ="р", площа=.4, місце_речі=запис)
    зн = Р.знахідка_уваги([е], [р], мета, зони_мети=зони)
    print(назва, "→ знахідок", len(зн), "очікується", чекано)
    вади += len(зн) != чекано
print("вад:", вади)
sys.exit(bool(вади))
