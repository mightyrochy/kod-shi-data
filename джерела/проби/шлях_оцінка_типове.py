"""Ділянка 8: ТИПОВІ ЗНАЧЕННЯ КАРТКИ ЯК ФАКТ. На записі 26.09 стилістка каже «за такої температури
верхній шар буде зайвим», хоч жінка погоди не називала: картка стоїть на «11:00, +18 °C» типово.
Друкує, звідки типове число, чи показ позначає його типовим у виклику коду, і як від нього
міняється вердикт тих самих речей. Запуск із `джерела`: python3 проби/шлях_оцінка_типове.py"""
import sys, json, re; sys.path.insert(0, '.')
import річ_з_фото as РФ, паспорт_нагоди as ПН, colorspace as cs
from міст_вхід import _збірка, _нормалізувати_вхід
T_ = open('показ.html', encoding='utf-8').read()
ряд = lambda взір: T_[:re.search(взір, T_).start()].count('\n') + 1
print('типове в DOM: показ.html:%d — <input id="сц-темп" value="18">; показ.html:%d — %s'
      % (ряд(r'id="сц-темп" value="18"'), ряд(r'const ТИПОВІ_ПОЛЯ_ВИПАДКУ'),
         re.search(r'const ТИПОВІ_ПОЛЯ_ВИПАДКУ = \{[^}]*\}', T_).group(0)))
зб = re.search(r'function зібратиВхід\(\)\{(.*?)\n  /\*', T_, re.S).group(1)
print('що шле код у міст (показ.html:%d): %s'
      % (ряд(r'function зібратиВхід'), ' '.join(зб.split())[:170]))
print('  → «година» й «темп_c» їдуть ЗАВЖДИ і БЕЗ позначки «типово»; позначку має лише нагода:')
print('  ТИПОВА_НАГОДА_РЕЧІ = «%s» (паспорт_нагоди.py:%d) — одне поле з трьох'
      % (ПН.ТИПОВА_НАГОДА_РЕЧІ, 1432))
вх = json.load(open('стенд_вх.json')); F, T, _з, _к = _збірка(_нормалізувати_вхід(dict(вх)))
жакет = dict(ід='ф1', фото='ф1', назва='жакет приталений', слот='верхній_шар', колір='хакі',
             ошатність=6, чия='моя', вимір=dict(lab=list(cs.hx('#7d7f63')), hex='#7d7f63', слово='хакі'))
for підпис, сц in (('картка як на записі (11:00, +18 °C)', dict(нагода='щоденне', година=11, темп_c=18)),
                   ('без погоди (вона її не казала)', dict(нагода='щоденне'))):
    в = РФ.вердикт(жакет, F, T, сц, типова_нагода=True)
    пог = [з for з in в['знахідки'] if з.get('правило') == 'K-WEA-01']
    без = [x for x in в['чекліст']['без_входу'] if x.startswith('температура')]
    print('%-38s → рівень «%s», знахідок погоди %d%s, «без входу»: %s'
          % (підпис, в['рівень'], len(пог), (' («%s»)' % пог[0]['суть'][:58]) if пог else '',
             (без[0] if без else 'про температуру мовчить')))
print('→ типове число картки код бере як сказане жінкою і виносить його їй реченням;')
print('  чесний шлях («без входу: температура не названа») вмикається лише коли поля НЕМА зовсім,')
print('  а показ поле завжди заповнює (показ.html:%d)' % ряд(r'темп_c:parseFloat\(\$\(.сц-темп'))
