"""Ділянка 8: ТИПОВІ ЗНАЧЕННЯ КАРТКИ ЯК ФАКТ. На записі 26.09 стилістка каже «за такої температури
верхній шар буде зайвим», хоч жінка погоди не називала: картка стоїть на «11:00, +18 °C» типово.
Друкує, звідки типове число, чи показ позначає його типовим у виклику коду, і як від нього
міняється вердикт тих самих речей. Запуск із `джерела`: python3 проби/шлях_оцінка_типове.py"""
import sys, json, re; sys.path.insert(0, '.')
import річ_з_фото as РФ, паспорт_нагоди as ПН, colorspace as cs
from міст_вхід import _збірка, _нормалізувати_вхід
T_ = open('показ.html', encoding='utf-8').read()
ряд = lambda взір: T_[:re.search(взір, T_).start()].count('\n') + 1
print('типове в DOM: показ.html:%d — <input id="сц-темп" value="18">; показ.html:%d — %s'
      % (ряд(r'id="сц-темп" value="18"'), ряд(r'const ТИПОВІ_ПОЛЯ_ВИПАДКУ'),
         re.search(r'const ТИПОВІ_ПОЛЯ_ВИПАДКУ = \{[^}]*\}', T_).group(0)))
зб = re.search(r'function зібратиВхід\(\)\{(.*?)\n  /\*', T_, re.S).group(1)
print('що шле код у міст (показ.html:%d): %s'
      % (ряд(r'function зібратиВхід'), ' '.join(зб.split())[:170]))
print('  → «година» й «темп_c» їдуть зі своїм ПОХОДЖЕННЯМ (`типові_поля`, В-2, 26.09.2026):')
print('  ТИПОВА_НАГОДА_РЕЧІ = «%s» · ТИПОВЕ_ПОЛЕ_ФОРМИ = «%s»'
      % (ПН.ТИПОВА_НАГОДА_РЕЧІ, ПН.ТИПОВЕ_ПОЛЕ_ФОРМИ))
_сц = dict(нагода='щоденне', місце='парк', година=11, темп_c=18, типові_поля=['година', 'темп_c'])
_п = ПН.паспорт_з_json('{}', _сц, 'гуляю з собаками в парку, вітер')
print('  паспорт із неторканої форми: мітки %s · рядок випадку рукам: «%s»'
      % (sorted(ПН.типові_з_форми(_п)), ПН.паспорт_рядком(_п)))
вх = json.load(open('стенд_вх.json')); F, T, _з, _к = _збірка(_нормалізувати_вхід(dict(вх)))
жакет = dict(ід='ф1', фото='ф1', назва='жакет приталений', слот='верхній_шар', колір='хакі',
             ошатність=6, чия='моя', вимір=dict(lab=list(cs.hx('#7d7f63')), hex='#7d7f63', слово='хакі'))
for підпис, сц in (('ДО    форма без походження (11:00, +18 °C)', dict(нагода='щоденне', година=11, темп_c=18)),
                   ('ПІСЛЯ показ назвав неторкані поля', dict(нагода='щоденне', година=11, темп_c=18,
                                                              типові_поля=['година', 'темп_c'])),
                   ('вона САМА назвала +18 °C', dict(нагода='щоденне', година=11, темп_c=18)),
                   ('без погоди (поля нема зовсім)', dict(нагода='щоденне'))):
    в = РФ.суд_у_виклику(жакет, F, T, сц, dict(джерело_полів={'нагода': ПН.ТИПОВА_НАГОДА_РЕЧІ}))
    пог = [з for з in в['знахідки'] if з.get('правило') == 'K-WEA-01']
    без = [x for x in в['чекліст']['без_входу'] if x.startswith('температура')]
    print('%-38s → рівень «%s», знахідок погоди %d%s, «без входу»: %s'
          % (підпис, в['рівень'], len(пог), (' («%s»)' % пог[0]['суть'][:58]) if пог else '',
             (без[0] if без else 'про температуру мовчить')))
print('→ ДО: типове число картки код брав як сказане жінкою і виносив їй реченням.')
print('  ПІСЛЯ (В-2): число з міткою `типове_форми` не їде в рядок випадку рук (див. вище), тож')
print('  суд речі з фото стоїть на тому ж чесному шляху, що й «поля нема зовсім»: «без входу:')
print('  температура не названа». Показ і далі шле значення (показ.html:%d) — але з походженням.'
      % ряд(r'темп_c:parseFloat\(\$\(.сц-темп'))
assert ПН.типові_з_форми(_п) == {'година', 'темп_c'}, 'мітка замовчування форми не стоїть'
assert '18 °C' not in ПН.паспорт_рядком(_п), 'замовчування форми досі їде в рядок випадку'
_сц_тип = dict(нагода='щоденне', година=11, темп_c=18, типові_поля=['година', 'темп_c'])
_в = РФ.суд_у_виклику(жакет, F, T, _сц_тип, dict(джерело_полів={'нагода': ПН.ТИПОВА_НАГОДА_РЕЧІ}))
assert not [з for з in _в['знахідки'] if з.get('правило') == 'K-WEA-01'], \
    'код досі виносить жінці погоду, якої вона не називала'
assert any(x.startswith('температура') for x in _в['чекліст']['без_входу']), \
    'чесного рядка «температура не названа» в чеклісті нема'
_в2 = РФ.суд_у_виклику(жакет, F, T, dict(нагода='щоденне', година=11, темп_c=18),
                       dict(джерело_полів={'нагода': ПН.ТИПОВА_НАГОДА_РЕЧІ}))
assert [з for з in _в2['знахідки'] if з.get('правило') == 'K-WEA-01'], \
    'названа нею температура перестала судитись — правило K-WEA-01 зламано'
print('В-2 на картці: типове число як її факт — нема')
