# -*- coding: utf-8 -*-
"""#324 · модель пише «#N·MM/низ» на речі, яка не комплект (живий прогін K-VAR-01, 25.09: светр-кейп «#257·34/низ»,
її джинси «#34·40/верх»). Що робить код: склад і слоти ті самі (половина діє лише для комплекту), а в
`розбір_блоків` — чи названо підпис, який код не прийняв. Пул — рука 1 `стенд_вх.json`. Друкує факт.
Запуск: cd джерела && python3 проби/половина_не_комплекту.py"""
import json, os, sys
Д = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, Д); os.chdir(Д)
import bridge as B
вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["гілка"] = 0
пул = json.loads(json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["руки"]["1"])["пул"]
верх, низ, вз, сум = (пул[с][0]["н"] for с in ("верх", "низ", "взуття", "сумка"))
від = lambda речі: json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=json.dumps(
    {"версія": "1", "образи": [{"ід": "о1", "речі": речі}]}, ensure_ascii=False)), ensure_ascii=False)))
чисто, з_половиною = від([верх, низ, вз, сум]), від([низ + "/верх", верх + "/низ", вз, сум])
склад = lambda в: sorted((о.get("слоти_н") or {}).values()) if (о := (в.get("образи") or [{}])[0]) else []
print("ФАКТ · слоти образу: без підписів %s · з «/верх»·«/низ» %s · однакові: %s" % (
    склад(чисто), склад(з_половиною), склад(чисто) == склад(з_половиною)))
пнк = (з_половиною.get("розбір_блоків") or {}).get("половина_не_комплекту")
print("ФАКТ · у звіті (розбір_блоків.половина_не_комплекту): %s" % (
    "; ".join("%s: %s як «%s» (слот речі — %s)" % (х["номер"], х["річ"], х["половина"], х["слот"]) for х in пнк) if пнк else "нічого"))
