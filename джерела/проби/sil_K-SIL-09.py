"""K-SIL-09 (сукня — моно-об'єкт силуету): `python3 проби/sil_K-SIL-09.py`.

ЧОМУ БУЛО «БЕЗ СЛІДУ»: емітент був, але жив усередині
`колір_образу.перевірка_value` — тобто ЗА ГЕЙТОМ ПЛОЩ. Ту гілку `review` виносить
лише коли КОЖНА річ образу несе `джерело_площі`, а воно ставиться тільки з
виміряних країв (`outfit.площі_з_геометрії` — «все або нічого»; сумка й прикраси
країв не мають зовсім). Покриття на живому шляху нульове, тож правило утримувалось
разом із п'ятьма колірними — хоч площа йому не потрібна: WHEN корпусу дослівно
каже «єдина велика поверхня образу — сукня (або одна річ)», тобто факт СЛОТА.
ЩО ПОКАЗУЄ ПРОБА: образ «сукня + взуття» дає рядок K-SIL-09 у вердикті; той самий
образ із доданим верхнім шаром (дві гардеробні поверхні) його не дає."""
import sys, pathlib, json
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import feed as Ф, bridge as B

вх = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml"); вх["гілка"] = 0
вх["сценарій"].update(темп_c=12, опади="ні")
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
сук = next(c for c in кат if c.get("слот") == "сукня")
вз = next(c for c in кат if c.get("слот") == "взуття")
шар = next(c for c in кат if c.get("слот") == "верхній_шар")
def суд(іди):
    вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=іди), ensure_ascii=False)))
    о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
    return вм, next((z for z in (о.get("знахідки") or []) if z.get("правило") == "K-SIL-09"), None)
вм, з = суд([сук["id"], вз["id"]])
print("сукня:", сук["назва"][:52])
print("площі виміряні?", "ні —" if any("площі не виміряні" in str(q.get("суть"))
      for q in (вм.get("питання") or [])) else "так —", "правило судить СЛОТИ, не площу")
print("сукня+взуття  K-SIL-09:", "НЕМА" if not з else
      "%s %.2f · %s · %s" % (з["сила"], з["сила_нп"], з["суть"][:46], з["регістр"]))
_, з2 = суд([сук["id"], вз["id"], шар["id"]])
print("+ верхній шар K-SIL-09:", "НЕМА (дві гардеробні поверхні)" if not з2 else з2["суть"])
assert з and not з2, (з, з2)
