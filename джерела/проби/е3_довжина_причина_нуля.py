"""15694: причина нульової ваги `верхнє_довжина` у звіті суду — код заяви, а не `джерело_сили`.

Кожна знахідка з вагою 0 мусить нести заяву, чий код називає причину нуля, і рядок
`суд_огляд.для_стиліста` мусить довезти цю заяву. Аргумент `--межі` — лише граничні входи."""
import collections, pathlib, sys
sys.path[:0] = [str(pathlib.Path(__file__).resolve().parents[1]), str(pathlib.Path(__file__).resolve().parent)]
ПРИЧИНА = {   # (правило, сила) → коди заяв, що кажуть, чому ваги нема
    ('K-OUT-02', 'утримано'): {'outer_length_vs_knee_not_judged'},     # бік коліна невідомий
    ('K-OUT-03', 'питання'): {'outer_edges_gap_no_length'},              # довжини нема у фіді
    ('K-OUT-03', 'утримано'): {'outer_edges_gap_not_judged',             # краї не від однієї точки
                               'outer_edges_gap_measured'},              # розрив у межах похибки
    ('K-OUT-04', 'soft'): {'cascade_declared_no_penalty'},              # каскад скасовує штраф (15568)
}


def main():
    """Лічба нулів за причиною; провал — нуль без заяви-причини чи рядок звіту без заяви."""
    import верхнє_довжина as Д, trace as Т, суд_огляд as СО, е3_довжина_набори as Н
    лік, провали = collections.Counter(), []
    for назва, функція, речі, тіло in Н.набори():
        if '--межі' in sys.argv and not назва.startswith('межа:'):
            continue
        for з in getattr(Д, функція)(речі, тіло):
            if з.get('сила_нп') != 0.0:
                continue
            коди = {з_.get('code') for з_ in з.get('заяви') or []} & ПРИЧИНА.get((з['правило'], з['сила']), set())
            рядок = СО.для_стиліста(dict(стани=dict(с=dict(знахідки=[з]))))['стани']['с'][0]
            if not коди or рядок.get('заяви') != з.get('заяви'):
                провали.append((назва, з['правило'], з['сила'], з.get('заяви')))
            лік[з['правило'], з['сила'], tuple(sorted(коди)), з.get('сила_нп_джерело')] += 1
        Т.ЗАПИСИ.clear()
    for к, н in sorted(лік.items(), key=str):
        print(н, *к)
    print('провалів', len(провали), провали[:3])
    sys.exit(1 if провали or not лік else 0)


if __name__ == '__main__':
    main()
