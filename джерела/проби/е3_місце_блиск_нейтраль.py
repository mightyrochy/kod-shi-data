"""Блиск і метали, нейтраль-якір читають запис місця речі: відоме місце — вирок, невідоме — «без входу» чи мовчання."""
import sys
sys.path.insert(0, ".")
import outfit as О, суд_блиск as СБ, colorspace as Ц, palette as П

ЗОЛ, СРБ = dict(метал="золото", полірування="полірований"), dict(метал="срібло", полірування="полірований")
F = Ц.features(Ц.hx("#deb295"), Ц.hx("#f1dbaa"), Ц.hx("#759087"))

def елементи(речі, стан="у_приміщенні"):
    return О.елементи([dict(площа=0.02, hex="#b0b0b0", **р) for р in речі], стан=стан)

def без_сили(я):
    return я["сила_переваги"] is None and я["вага_вікна"] == 0.0

def правила(зн):
    return {(з["правило"], з["сила"] == "питання") for з in зн}

def головна():
    """Метал з невідомим місцем — «без входу», з відомим (слово стилістки, тип, вимір) — вирок за записом."""
    інші = [dict(id="к", слот="каблучка", **СРБ), dict(id="б", слот="браслет", **СРБ)]
    for слово, чекаємо in (("так", False), ("ні", False), (None, True)):
        намисто = dict(id="н", слот="намисто", **ЗОЛ, **(dict(місце_стилістки=dict(біля_обличчя=слово)) if слово else {}))
        е = елементи([намисто] + інші)
        assert "near" in е[0] and е[0]["near"] is None, "near елемента — лише вимір, не стала слота"
        з = СБ.метали(е, F, драп=dict(метал="срібло"), речі=[намисто] + інші)
        print("метали, намисто", слово, "→", sorted(правила(з)))
        assert ((("K-CRA-07", True) in правила(з)) and (("K-COL-06-M", True) in правила(з))) == чекаємо
        assert чекаємо or {"K-CRA-07", "K-COL-06-M"} <= {п for п, _ in правила(з)}
    # блиск: сусідство — одна відома зона; невідома зона (своя чи матової між ними) — мовчання
    пари = (([dict(id="с", слот="сережки", блиск=2), dict(id="н", слот="намисто", блиск=2, місце_стилістки=dict(біля_обличчя="так"))], True),
            ([dict(id="с", слот="сережки", блиск=2), dict(id="н", слот="намисто", блиск=2)], False),
            ([dict(id="п", слот="пояс", блиск=2), dict(id="с", слот="сумка", блиск=2)], False))
    for речі, чекаємо in пари:
        з = СБ.блиск_бюджет(елементи(речі))
        print("блиск", [р["слот"] for р in речі], "→", [x["правило"] for x in з])
        assert bool(з) == чекаємо
    # нейтраль-якір: слот без факту типу й без запису від викликача — вікно не діє; з записом — діє; факт типу — діє
    драп, F2 = dict(метал="срібло", білий="оптичний"), Ц.features(Ц.hx("#c9b183"), Ц.hx("#f1dbaa"), Ц.hx("#759087"))
    без = П.нейтраль_якір(F2, source="protocolized", слот="верх", драп=драп)
    з_записом = П.нейтраль_якір(F2, source="protocolized", слот="верх", near=0.9, драп=драп)
    факт = П.нейтраль_якір(F2, source="protocolized", слот="сережки", драп=драп)
    print("якір: верх без запису", (без["near"], без["вільно"]), "· з записом 0.9", (з_записом["near"], з_записом["вільно"]),
          "· сережки (факт типу)", (факт["near"], факт["вільно"]))
    assert без["near"] is None and без["вільно"] and без_сили(без)
    assert з_записом["near"] == 0.9 and not з_записом["вільно"]
    assert факт["near"] == 1.0 and not факт["вільно"]

if __name__ == "__main__":
    головна()
