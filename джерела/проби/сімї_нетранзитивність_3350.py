"""3350: факти групування K-COMP-03, без зміни продукту чи нової політики.
Кешовані Lab і справжнє вікно каталогу; площа 0.2 — штучний вхід, не образ.
Жадібна лічба — лише контрфакт; фото очима тут не оцінюються.
"""
import gzip, itertools, json, os, subprocess, sys, tempfile
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import колір_образу as КО, колір_річ as КР, feed as Ф

def контрфакт(послідовність):
    """Друкувана лічба за першим представником, не алгоритм продукту."""
    групи = []
    for е in послідовність:
        if not any(КО.відношення(е, г, "same_hue", певність=False) == "так" for г in групи):
            групи.append(е)
    return len(групи)

if __name__ == "__main__":
    тека = Path(__file__).resolve().parents[1]
    записи = json.load(gzip.open(тека / "каталог_кадри.json.gz"))["записи"]
    іди = ["ж-00079@wearme.ua", "ж-04550@wearme.ua", "ж-00472@gepur.com",
           "ж-01503@wearme.ua", "ж-01513@wearme.ua"]
    елементи = [dict(річ=і, lab=записи[і][0]["lab"], площа=0.2) for і in іди]
    for е in елементи:
        е.update(нейтраль=КО.нейтраль(е["lab"]), сім_я=КО.сім_я(е["lab"]))
        print(е, "коло", КО.запис_кольору(е)["коло"], "кадр", записи[е["річ"]][0]["файл"])
    for а, б in itertools.combinations(елементи[:3], 2):
        print("пара", а["річ"], б["річ"], КО.розкид_тону_на_колі(а, б),
              КО.відношення(а, б, "same_hue", певність=False))
    print("контрфакт: групи трійки за всіма порядками", [контрфакт(п) for п in itertools.permutations(елементи[:3])])
    print("ДО=ПІСЛЯ, контроль площа=0.2, чинний K-COMP-03", КО.сім_ї_образу(елементи))
    дані = subprocess.check_output(["git", "-C", str(тека.parent), "show", "HEAD:каталог_повний.xml.gz"])
    дескриптор = os.memfd_create("3350-каталог")  # розпакування лише в пам'ять
    os.write(дескриптор, gzip.decompress(дані))
    with tempfile.TemporaryDirectory(prefix="3350-") as тимчасова:
        каталог = Ф._прочитати_каталог(f"/proc/self/fd/{дескриптор}", ліміт_фото=0,
                    кеш=str(Path(тимчасова) / "кеш.json"), збагачення=Ф.читати_збагачення())["каталог"]
    os.close(дескриптор)
    річ = next(р for р in каталог if р["id"] == "ж-00006@stolyarchuk.com.ua")
    print("каталог", len(каталог), "вікно", річ["id"], КР.не_вимір(річ), "сім'я", КР.сім_я_меж(річ), "same_hue із собою", КО.відношення(річ, річ, "same_hue", певність=False))
