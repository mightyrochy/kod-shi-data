def контрфакт(послідовність):
    """Друкувана лічба за першим представником, не алгоритм продукту."""
    групи = []
    for е in послідовність:
        if not any(КО.відношення(е, г, "same_hue", певність=False) == "так" for г in групи):
            групи.append(е)
    return len(групи)

