# -*- coding: utf-8 -*-
"""Д-1: яка частка каталогу не потрапляє в пул НІКОЛИ, і як часто повторюється решта.

Три різні сцени × три сіди = 18 пулів (рука 1 і рука 2 кожного прогону). Проба
друкує: скільки РІЗНИХ речей каталогу побачила модель за всі 18 разів, скільки
речей стоїть у кожному пулі, топ-10 найчастіших речей і в яких слотах вони сидять.
Річ, що є в кожному пулі, — це не «улюблена модель», а слот, де квота семплера
більша за сам слот (`повтор_страти.py`): такий слот віддає себе цілком щоразу.
Прогін: python3 проби/повтор_каталог.py    (~2.5 хв: дев'ять повних збирань)
"""
import collections, json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed as Ф, bridge as B, міст_пакет as МП
СЦЕНИ = (dict(нагода="робота", місце="офіс", година=9, темп_c=18, дрес_код="business_casual"),
         dict(нагода="побачення", місце="ресторан", година=19, темп_c=22, дрес_код="cocktail"),
         dict(нагода="щоденне", місце="вулиця", година=12, темп_c=5, дрес_код=None))
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), каталог=Ф.каталог_на_диску("каталог_повний.xml"))
пули, слот_речі = [], {}
for сцена in СЦЕНИ:
    for сід in (7, 4242, 31337):
        json.loads(B.виклик("запити", json.dumps(dict(вх, сценарій=сцена, сід=сід), ensure_ascii=False)))
        for п in [p for p in МП._КЕШ_ПАКЕТА.values() if p.get("кандидати")]:
            пули.append({r.get("id") for v in п["кандидати"].values() for r in v})
            for с, v in п["кандидати"].items():
                for r in v: слот_речі[r.get("id")] = с
КАТАЛОГ = len(МП.каталог_останнього_пакета())
лічба = collections.Counter(i for п in пули for i in п)
print("%d пулів (%d сцен × %d сіди × 2 руки), у пулі в середньому %.0f речей"
      % (len(пули), len(СЦЕНИ), 3, sum(len(п) for п in пули) / len(пули)))
print("каталог %d речей → різних речей у всіх %d пулах разом: %d = %.1f %%"
      % (КАТАЛОГ, len(пули), len(лічба), 100.0 * len(лічба) / КАТАЛОГ))
print("НЕ побачила модель жодного разу: %d речей = %.1f %% каталогу"
      % (КАТАЛОГ - len(лічба), 100.0 * (КАТАЛОГ - len(лічба)) / КАТАЛОГ))
for поріг in (len(пули), len(пули) * 3 // 4, len(пули) // 2):
    скільки = sum(1 for v in лічба.values() if v >= поріг)
    print("   речей, що є щонайменше в %2d із %d пулів: %4d (%.0f %% типового пулу)"
          % (поріг, len(пули), скільки, 100.0 * скільки * len(пули) / max(sum(len(п) for п in пули), 1)))
print("топ-10 найчастіших: %s" % ", ".join(
    "%s×%d (%s)" % (ід.split("@")[0], n, слот_речі.get(ід)) for ід, n in лічба.most_common(10)))
