"""Рядок 2340 (огляд Codex P1 у #659): чи доходить до ранжування `повнота_набору` гейт ЛИШЕ про її річ з фото, який `_суд_складу`
знизив би лише після вибору. Живий шлях руки 1: стенд, 3 сцени × її закріплена річ (верх, низ, взуття, сумка; 4 кольори каталогу),
схему обрала вона (`гілка`=0: K-PAL-03 — гейт), 4 образи з пулу, 2 з діркою (без взуття чи сумки); суддя — `від_моделі`. Факт —
образів, де суддя сам зняв K-PAL-03 з її речі (`річ_з_фото.без_замків`), гейтів лише про неї в ранжуванні, рук зі зміною вибору."""
import json, sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, повнота_образу as ПО, colorspace as cs
вх = json.load(open("стенд_вх.json"))
СЦЕНИ = [dict(нагода='робота', місце='офіс_корпоративний', година=10, темп_c=18), dict(нагода='побачення', місце='ресторан_районний',
         година=19, темп_c=14), dict(нагода='щоденне', місце='парк', година=15, темп_c=5, опади='дощ')]
B.виклик('запити', json.dumps(dict(вх, сценарій=СЦЕНИ[0]), ensure_ascii=False)); кат = B.каталог_останнього_пакета()
рук = образів = гейтів = знято = її_гейтів = змін = 0
def ключ(к, с, суд):
    ч = ПО._чому_не_можна(суд); бл = [b for b in ((к.get("структура") or {}).get("блокери") or []) if (b or {}).get("код")]
    return (1 if ч else 0, 1 if (ч and ПО._чому_не_можна(dict(суд, структура=dict(ок=True, блокери=[])))) else 0, len(бл), -len(с["ід"]))
for сц in СЦЕНИ:
    for слот in ("верх", "низ", "взуття", "сумка"):
        for р in [r for r in кат if r.get("слот") == слот and r.get("lab")][7::211][:4]:
            річ = dict(ід='ф1', фото='ф1', назва=р['назва'][:40], слот=слот, колір=р.get('колір_ім'), чия='моя', закріплена=True,
                       вимір=dict(lab=list(р['lab']), hex=cs.hex_з_lab(tuple(р['lab'])), слово=р.get('колір_ім')))
            д = dict(вх, сценарій=сц, паспорт=dict(сц, речі_з_фото=[річ]), варіантів=10, бюджет_символів=120000, без_фото=1, гілка=0)
            з = json.loads(B.виклик('запити', json.dumps(д, ensure_ascii=False))); пул = з['пакети']['1']['пул']
            н = lambda с, i: пул[с][i % len(пул[с])]['н'] if пул.get(с) else None
            обр = [dict(ід='о%d' % i, речі=[x for x in [н('верх', i), н('низ', i), (н('взуття', i) if i % 2 else None),
                   (н('сумка', i) if i % 2 or слот == 'взуття' else None), н('прикраси', i)] if x]) for i in range(1, 5)]
            в = json.loads(B.виклик('від_моделі', json.dumps(dict(д, текст_моделі=json.dumps(dict(версія='1', образи=обр), ensure_ascii=False)), ensure_ascii=False)))
            канд = з['кандидати']; сл = ПО._словник_речей(канд, None); зн = ПО._за_номером(канд); рук += 1; до, піс = [], []
            for к in (в.get('вердикт') or {}).get('образи') or []:
                с = ПО._склад_вибору(к, сл, зн)
                if len(с["ід"]) < 2: continue
                суд = ПО._суд_складу(к, с["ід"], ПО._свідомі_ключі(к, с["ід"], сл, зн), ПО._її_речі(с["ід"], сл), сл, зн)
                свої = set(ПО._її_речі(с["ід"], сл)); знято += any(z.get("правило") == "K-PAL-03" and z.get("регістр") == "репліка" and
                    свої >= set(ПО._речі_гейтів([z], с["ід"], сл, зн)) > set() for z in к.get("знахідки") or [] if isinstance(z, dict))
                образів += 1; гейтів += bool(ПО._чому_не_можна(dict(к, структура=dict(ок=True, блокери=[]))))
                її_гейтів += bool(ПО._чому_не_можна(к)) != bool(ПО._чому_не_можна(суд))
                до.append((ключ(к, с, к), к.get("ід"))); піс.append((ключ(к, с, суд), к.get("ід")))
            змін += bool(до) and min(до)[1] != min(піс)[1]
print("рук %d · образів %d · з гейтом %d · суддя сам зняв K-PAL-03 з її речі %d · з гейтом ЛИШЕ про її річ до ранжування %d"
      " · рук, де вибір найкращого міняється %d" % (рук, образів, гейтів, знято, її_гейтів, змін))
