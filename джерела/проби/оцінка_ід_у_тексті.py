"""КАРТКА-СЛОВА (рядок 3658): ід речі на картці оцінки. Друкує, чи несе промпт ОЦІНКА заборону ідів у «text»,
і що бачить звірка стенда «6: … ідів фото» на записаному тексті ЖИВІ-14 №10 — давня (лише «ф1·2») і нова (ІД_ОЦІНКИ).
Запуск: cd джерела && python3 проби/оцінка_ід_у_тексті.py"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import оцінка_образу as О
print("промпт ОЦІНКА: «a \"text\" never writes one» —", any('a "text" never writes one' in п for п in О.ОЦІНКА.правила))
# та сама регулярка, що `ІД_ОЦІНКИ` у стенді (\p{L} → [^\W\d_])
НОВА = re.compile(r"(?:^|[\W_])(?:[фpр]\d+(?:[·\-]\d+)?|[cс]\d+|f-o\d+-\d+)(?![^\W_])")
for т in ("Замінивши чорну сорочку на твою білу блузку (артикул р2-3), ти пом’якшиш контраст у зоні обличчя.",
          "Замінивши чорну сорочку на твою білу блузку, ти пом’якшиш контраст у зоні обличчя."):
    print("давня звірка ловить: %-5s · нова: %-5s · %s" % (bool(re.search(r"ф\d·\d", т)), bool(НОВА.search(т)), т[:60]))
