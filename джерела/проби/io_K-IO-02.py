# -*- coding: utf-8 -*-
"""K-IO-02 (протокол браку даних: не вигадувати, не припускати мовчки, питати ОДИН
раз і лише про те, чого бракує).

ДО ПРАВКИ: виконувана форма правила БУЛА — `profile.аудит` рахує
`бракує_онбордингу` (перелік питань рівно про порожні поля й жодного зайвого)
разом із політикою «про що не питати проактивно», а `pipeline.підготувати` кладе
це в `бракує_входів`. Читав це поле РІВНО ОДИН споживач: `print` під
`if __name__ == "__main__"` самого `pipeline`. Ні міст, ні показ, ні модель його
не бачили — тобто код знав, чого йому бракує, і мовчав. А мовчазна підстановка —
це саме те, що правило забороняє.
ПІСЛЯ: список їде у відповідь `запити` полем `бракує_входів` разом із `не_питати`.
Проба друкує, скільки питань і які, і перевіряє, що заповнене поле з переліку
зникає — тобто питають рівно про брак, а не «усе одразу»."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
б = r.get("бракує_входів") or {}
питання = б.get("онбординг") or []
print("питань онбордингу у відповіді `запити`: %d" % len(питання))
for q in питання[:3]:
    print("   ·", q[:88])
print("не питати проактивно:", json.dumps(б.get("не_питати"), ensure_ascii=False)[:96])
assert питання, "перелік того, чого бракує, мусить виходити назовні, а не вмирати в pipeline"
assert б.get("не_питати"), "політика «про що не питати» їде разом із питаннями"
# заповнене поле зникає з переліку: питають рівно про брак
r2 = json.loads(B.виклик("запити", json.dumps(
    dict(вх, драп=dict(білий="вершковий", метал="золото", нейтралі="теплі")),
    ensure_ascii=False)))
питання2 = (r2.get("бракує_входів") or {}).get("онбординг") or []
print("після трьох відповідей драпіровки: %d питань (було %d) — зникли саме вони"
      % (len(питання2), len(питання)))
assert len(питання2) == len(питання) - 3, "питати мусить лише про те, чого бракує"
