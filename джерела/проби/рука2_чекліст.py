"""Р2-2в (рядок 554): чи доходить знахідка вимкненого руці 2 правила до чекліста (K-SYS-08/09, палітра,
аксесуари). Пул руки 1 (`запити`, каталог_повний, стенд_вх, сід 3); на кожне правило переліку — 12 випадкових
образів, суд під `правило_руки2.вимкнено(коди)`. Друкує пункти чекліста, де стоїть знахідка вимкненого правила.
Запуск: cd джерела && python3 проби/рука2_чекліст.py"""
import json, sys, random, pathlib, collections; sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B, pipeline as ПЛ, правило_руки2 as ПР2
from композитор_річ import _у_річ
вх = dict(json.load(open("стенд_вх.json")), каталог="каталог_повний.xml", сід=3)
к = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False))).get("кандидати") or {}
за_ід = {x["id"]: x for x in B.каталог_останнього_пакета()}
F, T, _з, kw = B._збірка(B._нормалізувати_вхід(B._застосувати_паспорт(dict(вх))))
пул = {с: [за_ід[x.get("id") or x.get("ід")] for x in (к.get(с) or []) if (x.get("id") or x.get("ід")) in за_ід] for с in ("верх","низ","сукня","взуття","сумка","прикраси")}
рнд = random.Random(1); лік = collections.Counter(); всього = 0
for з in ПР2.ПЕРЕЛІК:
    for i in range(12):
        осн = [рнд.choice(пул["сукня"])] if i % 2 else [рнд.choice(пул["верх"]), рнд.choice(пул["низ"])]
        речі = [_у_річ(dict(r), r.get("слот") or "верх", T) for r in осн + [рнд.choice(пул[с]) for с in ("взуття","сумка","прикраси") if пул[с]]]
        with ПР2.вимкнено(з["коди"]):
            в = ПЛ.перевірити_образ(F, речі, тіло=T, **dict(kw))
        ч = в.get("чеклісти") or {}
        всього += 1
        for сп in ("надлишок", "прісність", "палітра", "аксесуари"):
            for п in ч.get(сп) or []:
                for (пр, _) in п.get("знахідки") or []:
                    if ПР2._у(пр, frozenset(з["коди"])):
                        лік[(з["ід"], сп, п.get("пункт"), пр, п.get("стан"))] += 1
print("образів %d · пунктів чекліста зі знахідкою вимкненого правила %d" % (всього, sum(лік.values())))
for k, v in sorted(лік.items()): print(k, v)
