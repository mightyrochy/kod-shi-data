"""Рядок 1421: чи правдива причина `why_her_eyes` при основі, яку обрала стилістка. Вхід — 39 прогонів
розбору 02.10 (`аудит/перевірки/rozbir_0210/а2/вибір_палітри.out.txt`: жінка, основа кодом, L, гама,
причини). Основу відновлено з ґратки (`міст_основи._ґратка_основ`), очі — з профілю `аудит/проби/жінки`.
ДО — суддя брав будь-який код переліку; ПІСЛЯ — `вибір_палітри._до_очей`: лишається лише при echo/set_off.
Друкує ще, скільки основ поточного переліку кожної жінки мають відношення до очей (поле `eyes` промпта).
Запуск із `джерела`: python3 проби/очі_основа_1421.py"""
import sys, pathlib, re, json, collections
К = pathlib.Path(__file__).resolve().parent.parent; sys.path.insert(0, str(К))
import міст_основи as МО, міст_вхід as МВ, вибір_палітри as ВП, внутрішня_мова as ВМ, palettes as ПЛ, colorspace as cs
ГАМА = {"muted": "приглушені", "medium": "середні", "vivid": "насичені"}
ґр, _ = МО._ґратка_основ()
def основа(код, L, гама):
    for к, (hexx, назва) in ґр.items():
        ч = к.split("·")
        if ВМ.код("color_name", ч[0]) == код and ч[2] == L and (ч[3] == ГАМА.get(гама) or ч[1] == "нейтраль"):
            ах = ч[1] == "нейтраль"
            return dict(ахром=ах, hex=hexx, сім_я=None if ах else (ПЛ.сім_я_тону(cs.lch(cs.hx(hexx))[2]) or [None])[0])
Т = dict(зріст=168, обхвати={"плечі": 98, "груди": 92, "талія": 74, "стегна": 99})
жін = {ж: json.load(open(К.parent / ("аудит/проби/жінки/%s.json" % ж), encoding="utf-8")) for ж in ("ж%d" % i for i in range(1, 9))}
F = {ж: МВ._features(dict(шкіра=д["skin"], волосся=д["hair"], очі=д["eyes"]))[0] for ж, д in жін.items()}
РЯД = re.compile(r"^(ж\d)_(\S+).*\n.*\n.*\n\s+ОБРАЛА:.*основа=b\d+\(ранг \d+, (\S+) L(\d+) (\w+)\) \[([^\]]*)\]", re.M)
Σ, зняті = collections.Counter(), []
for ж, сц, код, L, гама, пр in РЯД.findall(open(К.parent / "аудит/перевірки/rozbir_0210/а2/вибір_палітри.out.txt", encoding="utf-8").read()):
    Σ["прогонів"] += 1
    if "why_her_eyes" not in пр: continue
    о = основа(код, L, гама); в = ВП._до_очей(о, F[ж]) if о else "?"
    Σ["why_her_eyes ДО прийнято"] += 1; Σ["ПІСЛЯ лишилось" if в else "ПІСЛЯ знято"] += 1
    if not в: зняті.append("%s_%s %s" % (ж, сц, код))
print("знято:", ", ".join(зняті))
for ж in жін:
    пер = ВП.перелік(dict(Т, шкіра=жін[ж]["skin"], волосся=жін[ж]["hair"], очі=жін[ж]["eyes"]))
    в = collections.Counter(о["очі"] for о in пер["основи"])
    print("%s очі %s · основ %d · echo %d · set_off %d" % (ж, пер["особа"]["eyes"]["family"], len(пер["основи"]), в["echo"], в["set_off"]))
print("ФАКТ · прогонів %(прогонів)d · why_her_eyes ДО прийнято %(why_her_eyes ДО прийнято)d · ПІСЛЯ лишилось %(ПІСЛЯ лишилось)d, знято %(ПІСЛЯ знято)d" % Σ)
