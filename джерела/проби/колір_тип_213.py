# -*- coding: utf-8 -*-
"""Тип кольору на межах: застарілі числа, невідомий тон поверхні та два кольори."""
import sys
sys.path.insert(0, ".")
import колір_річ as КР, фід_збагачення as ФЗ, verify as V, outfit as О
from жнива_колір import за_вікном_слова
from суд_від_моделі import _елемент_точки

в = V.ЛЕКСИКОН["синій"]
нв = ФЗ.не_вимір_кольору(в, "синій", "shop_word")
р = dict(id="синя", слот="верх", hex="#ffffff", lab=(100, 0, 0),
         колір_тип="інтервал", колір_не_вимір=нв, площа=1)
е = О.елементи([р])[0]
assert КР.точка_кольору(е) is None and е["lab"] is None
assert КР.межі_кольору(е) == КР.межі_кольору(р)
assert КР.точка_кольору(_елемент_точки((р, "верх", 100, 0, 0))) is None
нев = dict(р, колір_тип="невідомо")
assert КР.межі_кольору(нев) is None and КР.точка_кольору(нев) is None
assert КР.точка_кольору(dict(hex="#ffffff")) is not None
сег = dict(lab=[35, 0, 0], hex="#525252", світлота=35, хрома=[3, 10], тон=None, частка=0.8)
сл = за_вікном_слова(сег, ["синій"])
assert сл["hex"] == сег["hex"] and КР.явний_тип_кольору(сл) == "інтервал"
з = dict(версія=2, колір_основний=сл, колір_другий=dict(слово="білий", hex="#fff000", частка=0.2))
assert ФЗ.lab_збагачення(з)[0] is None
зап = dict(lab=None, колір_тип="інтервал")
ФЗ.накласти_колір(зап, з)
assert зап["lab"] is None and all(КР.точка_кольору(c) is None for c in зап["colors"])
assert зап["колір_другий"]["колір_вимір"]["hex"] == "#fff000"
без = КР.без_входу_кольору("K-PAL-09", [(нев,)], "cannot_tell_item_holds_scheme_hue")
assert без["сила_нп_джерело"] == "no_input:колір_не_вимір" and без["сила_нп"] == 0
print("Типи: інтервал зі старим білим Lab не вимір; невідомо без точки; фото другого кольору збережено; 2.12 передає інтервал")
