# Рядок 204 (питання власника «як тоді розглядаються сарафани, якщо це не сукні?»):
# 60 із 86 сарафанів не мали типу ЗОВСІМ — шар формальності мовчав, і лляний сарафан
# ішов у весільні 7–9 нарівні з вечірньою. Тепер це форма сукні зі смугою 4–6.
import sys, os, collections, importlib.util
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import feed, фід_каталог as ФК, фід_слот as НОВ, формальність as ФН
def _до(зм, імя):
    сп = importlib.util.spec_from_file_location("до_" + імя, os.environ.get(зм, "/tmp/204/до_%s.py" % імя))
    м = importlib.util.module_from_spec(сп); сп.loader.exec_module(м); return м
СТАР, ФД = _до("DO_FID_SLOT", "фід_слот"), _до("DO_FORM", "формальність")
кат = ФК._прочитати_каталог(feed.каталог_на_диску("каталог_повний.xml"), 0)["каталог"]
оф = lambda r: {"назва": r.get("назва"), "категорія": r.get("категорія"), "параметри": r.get("параметри") or {}}
тип = lambda м, r: м._тип_речі_обчислити(оф(r), r.get("слот"))
с = [r for r in кат if "сарафан" in (r.get("назва") or "").lower()]
без = lambda м: sum(1 for r in с if тип(м, r) is None)
print("сарафани %d · слоти %s · без типу %d → %d · типи ПІСЛЯ %s"
      % (len(с), dict(collections.Counter(r.get("слот") for r in с)), без(СТАР), без(НОВ),
         dict(collections.Counter(тип(НОВ, r) for r in с))))
впало = без(НОВ)
ел = lambda м, r: {"тип": тип(м, r), "тип_модифікатор": м.тип_модифікатор(оф(r), r.get("слот")),
                   "матеріал": r.get("матеріал"), "волокно": r.get("волокно"),
                   "текстура": r.get("текстура"), "назва": r.get("назва")}
стеля = lambda мф, мс, r: мф.інтервал_формальності(ел(мс, r))[1]
мали = [(стеля(ФД, СТАР, r), стеля(ФН, НОВ, r)) for r in с]
рост = sum(1 for a, b in мали if a is not None and b > a)
print("стеля: мовчала й заговорила %d · впала %d · ЗРОСЛА %d"
      % (sum(1 for a, _ in мали if a is None),
         sum(1 for a, b in мали if a is not None and b < a), рост))
впало += рост
# K-KOH-05 на весіллі 7–9: доти правило мовчало (типу нема), тепер каже «нижче».
сцен = {"діапазон": (7, 9), "risk_posture": "neutral"}
льон, чов = ({"річ": "с1", "слот": "сукня", "назва": "Сарафан лляний", "волокно": "льон"},
             {"річ": "в1", "слот": "взуття", "назва": "Човники", "тип": "човники"})
зн = lambda мф, т: [z for z in мф.формальність_образу([dict(льон, тип=т), чов], сцен)
                    if z.get("правило") == "K-KOH-05"]
д, п = зн(ФД, None), зн(ФН, "сарафан")
print("K-KOH-05 весілля 7–9 · лляний сарафан: %d → %d%s"
      % (len(д), len(п), (" · «%s»" % п[0]["суть"]) if п else ""))
впало += len(д) + (0 if п else 1)
print("ВПАЛО %d" % впало)
