"""ФАКТИ ДНЯ ВІД МОДЕЛІ (рядок 209, знахідки З-5, З-5г, З-1б проходу 24.09 на живих локальних моделях).
Модель дописує в паспорт температуру, годину, тривалість і місце там, де жінка про це не казала, — і
навіть ПОВЕРХ її слів: на похороні вона написала «надворі +6», модель поклала 18 °C, і рядок випадку,
що йде в усі чотири промпти й у шапку образів, сказав їй «18 °C». Ту саму «18» модель підставила в
чотири паспорти з п'яти. Плюс З-1б: приклад із промпта рядка 189 («по-дівчачому») вона повернула як
`реєстр_людини` на офісі — а це вхід передфільтра K-REG-02, тобто ПУЛ. Проба бере п'ять паспортів того
проходу дослівно (таблиця З-5г звіту) плюс чотири випадки числа СЛОВАМИ (повернення #293) і рахує факти
БЕЗ ОПОРИ в її словах ДО і ПІСЛЯ. Запуск: cd джерела && python3 проби/fakty_dnia_209.py"""
import sys, pathlib, json
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import паспорт_нагоди as ПН
В, Д = dict(типи=[], тканини=[], принти=[], кольори=[], зони=[]), dict
ПРОГОНИ = [   # (мітка, слова жінки, паспорт від моделі, що код МУСИТЬ лишити)
    ("типовий сід 7", "робочий день в офісі, дрес-код business casual, без підборів",
     Д(нагода="робота", місце="офіс_креативний", формат="приміщення", темп_c=18, година=11,
       тривалість_год=11, реєстр_людини=["романтичний"]), Д(місце="офіс_креативний", формат="приміщення")),
    ("похорон сід 5", "похорон, надворі +6", Д(місце="парк", темп_c=18, година=11), Д(темп_c=6.0)),
    ("мороз сід 9", "іду в місто на цілий день, надворі мороз мінус вісім і сніг", Д(темп_c=-8, година=9), Д(темп_c=-8.0)),
    ("весілля сід 11", "весілля з пʼятої вечора", Д(година=17, темп_c=18), Д(година=17)),
    ("Ір сід 3", "для авто та на урок, надворі дощ",
     Д(місце="парк", формат="просто неба", темп_c=18, година=11, тривалість_год=9), Д(формат="просто неба")),
    # ЧИСЛО СЛОВАМИ — теж її число (повернення #293): голосовий ввід дає саме слова, а
    # плитка стенда каже 18, тож невзяте число моделі = втрачене її
    ("театр +14", "іду в театр, на вулиці плюс чотирнадцять", Д(темп_c=14), Д(темп_c=14.0)),
    ("собаки +16", "гуляю з собаками, надворі плюс шістнадцять", Д(темп_c=16), Д(темп_c=16.0)),
    ("мінус пʼять", "надворі мінус пʼять", Д(темп_c=-5), Д(темп_c=-5.0)),
    ("плюс тридцять", "спека, плюс тридцять", Д(темп_c=30), Д(темп_c=30.0))]
ПОЛЯ, без_опори, згублено, впало = ("темп_c", "година", "тривалість_год", "місце", "формат", "реєстр_людини"), [0, 0], [0, 0], 0
for мітка, слова, від, треба in ПРОГОНИ:
    п = ПН.паспорт_з_json(json.dumps(dict(від, подія=мітка, вето=В), ensure_ascii=False), слова=слова, сценарій={})
    for i, є in enumerate([від, {k: п.get(k) for k in ПОЛЯ if п.get(k) not in (None, "", [], "невідомо")}]):
        без_опори[i] += len([k for k in ПОЛЯ if є.get(k) not in (None, "", [], "невідомо") and k not in треба])
        згублено[i] += len([k for k in треба if є.get(k) != треба[k]])
    зайве = {k: п.get(k) for k in ПОЛЯ if п.get(k) not in (None, "", [], "невідомо") and k not in треба}
    if зайве: впало += 1; print("   ✗ %-16s лишилось без опори: %s" % (мітка, зайве))
    print("   %-16s рядок випадку: %s" % (мітка, ПН.паспорт_рядком(п)))
print("прогонів %d · фактів дня БЕЗ ОПОРИ в її словах: ДО %d → ПІСЛЯ %d · названого нею згублено: ДО %d → ПІСЛЯ %d"
      % (len(ПРОГОНИ), без_опори[0], без_опори[1], згублено[0], згублено[1]))
assert (без_опори[1], згублено[1], впало) == (0, 0, 0), "вигадане лишилось або назване нею згублено"
