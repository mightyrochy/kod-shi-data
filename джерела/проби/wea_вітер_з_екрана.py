"""П-1: чи доїжджає вітер з екрана до коду. `python3 проби/wea_вітер_з_екрана.py`.

Плитка «Вітер» має три бали (безвітря / помірний / сильний). Показ слав САМ БАЛ
(0/1/2) під іменем `вітер`, а всі споживачі читають це поле як м/с: слот верхнього
шару від 6 (`композитор_збирання`), легкий кльош від 8 (`суд_погода`), `wind_ms`
моделі від 6 (`сценарій.ВІТЕР_ПОМІТНИЙ`). Проба друкує, що бачить кожен із трьох
на кожному балі. ДО правки рядок «сильний» був порожній у всіх трьох колонках."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import сценарій as СЦ, outfit as O, суд_погода as СП

сукня = dict(id="с-1", слот="сукня", hex="#334455", назва="Сукня кльош",
             матеріал="шифон", волокно="шовк", тип="сукня", крій="кльош")
речі = [сукня]
print("шкала показу → м/с: %s · поріг слота шару 6 · поріг кльошу 8 · wind_ms від %g"
      % (СЦ.ВІТЕР_БАЛИ, СЦ.ВІТЕР_ПОМІТНИЙ))
for бал in (None, 0, 1, 2):
    сц = {"нагода": "прогулянка", "місце": "парк", "година": 12, "темп_c": 14,
          "формат": "просто неба"}
    if бал is not None:
        сц["вітер_бал"] = бал
    нагода, незнайомі = СЦ.з_показу(сц)
    мс = нагода.get("вітер")
    E = O.елементи(речі, стан="надворі")
    кльош = [z for z in СП.погода(E, темп_c=14, вітер=мс, стан="надворі", речі=речі)
             if "кльош" in z["суть"]]
    день = СЦ.день_кодами(нагода)
    print("бал=%-4s → вітер=%-5s м/с · слот шару тримає: %-3s · кльош: %-4s · "
          "модель бачить wind_ms=%-5s%s"
          % (бал, мс, "так" if (мс or 0) >= 6 else "ні",
             "так" if кльош else "нема", день.get("wind_ms"),
             " · НЕЗНАЙОМІ: %s" % незнайомі if незнайомі else ""))
