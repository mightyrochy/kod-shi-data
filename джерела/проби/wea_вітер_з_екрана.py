"""П-1 і крок вітру кореня Е2-смуга-погоди: що бачить код на кожному балі плитки «Вітер».
`python3 проби/wea_вітер_з_екрана.py`. Бал (0/1/2) показ шле як `вітер_бал`; `з_показу` ставить смугу
`смуга_вітру` (calm / moderate / strong) і м/с не має. Друкує смугу, шар (композитор), кльош (суд погоди),
косий дощ (`сильна_непогода`) і `wind_band` моделі на кожному балі; `м/с у нагоді` має лишатись None."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import сценарій as СЦ, паспорт_нагоди as ПН, outfit as O, суд_погода as СП

речі = [dict(id="с-1", слот="сукня", hex="#334455", назва="Сукня кльош",
             матеріал="шифон", волокно="шовк", тип="сукня", крій="кльош")]
print("смуги вітру: %s · бал → смуга: %s" % (СЦ.СМУГИ_ВІТРУ, СЦ.СМУГА_З_БАЛА))
for бал in (None, 0, 1, 2, "2", 7):
    сц = {"нагода": "прогулянка", "місце": "парк", "смуга_погоди": 'cool', "формат": "просто неба"}
    if бал is not None:
        сц["вітер_бал"] = бал
    нагода, незнайомі = ПН.з_показу(сц)
    см = нагода.get("смуга_вітру")
    кльош = [z for z in СП.погода(O.елементи(речі, стан="надворі"), смуга_погоди='cool', смуга_вітру=см,
                                  стан="надворі", речі=речі) if "кльош" in z["суть"]]
    print("бал=%-4s → смуга=%-8s · шар від вітру: %-3s · кльош: %-4s · косий дощ: %-20s · wind_band=%-8s"
          " · м/с у нагоді: %s%s"
          % (бал, см, "так" if см == СЦ.СИЛЬНИЙ_ВІТЕР else "ні", "так" if кльош else "нема",
             СЦ.сильна_непогода("дощ", "cool", None, см), СЦ.день_кодами(нагода).get("wind_band"),
             нагода.get("вітер"), " · НЕЗНАЙОМІ: %s" % незнайомі if незнайомі else ""))
