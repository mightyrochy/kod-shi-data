# -*- coding: utf-8 -*-
"""Рядок 203: «бавовна» читалась як «вовна» — бавовняна річ судилась зимовою.
ДО — реєстр із голим `вовн`, ПІСЛЯ — з `(?<!ба)вовн`. Решта реєстру не чіпана.
Запуск: cd джерела && python3 проби/bavovna_203.py"""
import collections, os, re, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as ФК, пакет_моделі as ПМ
кат = ФК._прочитати_каталог(feed.каталог_на_диску(), ліміт_фото=0)["каталог"]
ГОЛИЙ = re.compile(r"\(\?<!ба\)вовн")
def до(r, темп):
    """Вирок `_жорстке_відсічення` ДО рядка 203: той самий код із голим `вовн`."""
    п = ПМ.re.search
    ПМ.re.search = lambda в, т, *а, **к: п(ГОЛИЙ.sub("вовн", в), т, *а, **к)
    try: return ПМ._жорстке_відсічення(r, темп_c=темп)
    finally: ПМ.re.search = п
слова = collections.Counter()
for r in кат:
    for м in re.findall(r"\w*вовн\w*", str(r.get("назва") or ""), re.I): слова[м.lower()] += 1
хибні = sum(n for с, n in слова.items() if с.startswith("ба"))
print("ФАКТ · слів із «вовн» у назвах: %d, з них «бавовн-» %d (%.0f %%) — саме вони й ловились"
      % (sum(слова.values()), хибні, 100.0 * хибні / max(1, sum(слова.values()))))
змін, прикл = collections.Counter(), []
for r in кат:
    for темп in (30.0, 26.0, 22.0, 16.0):
        а, б = до(r, темп), ПМ._жорстке_відсічення(r, темп_c=темп)
        if а == б: continue
        змін["%s°C · %s" % (темп, r.get("слот"))] += 1
        if len(прикл) < 4 and темп == 26.0: прикл.append((r["id"], str(r.get("назва"))[:52], а, б))
print("ФАКТ · вироків `_жорстке_відсічення`, що змінились: %d · %s"
      % (sum(змін.values()), dict(змін.most_common(8))))
for ід, н, а, б in прикл:
    print("ФАКТ · %s «%s» · ДО %s → ПІСЛЯ %s" % (ід, н, а, б or "лишається"))
ціле = [r for r in кат if re.search(r"(?<!ба)вовн", str(r.get("назва") or ""), re.I)]
print("ФАКТ · справжня вовна не зачеплена: %d речей, вирок при 30 °C незмінний у %d"
      % (len(ціле), sum(1 for r in ціле if до(r, 30.0) == ПМ._жорстке_відсічення(r, темп_c=30.0))))
ІНШІ = (("пальто", "напівпальто/полупальто"), ("шуб", "екошуба"), ("тепл", "утеплена"))
for к, чому in ІНШІ:
    n = sum(1 for r in кат if re.search(k := к, str(r.get("назва") or ""), re.I)
            and not re.search(r"(?<![^\W\d_])" + k, str(r.get("назва") or ""), re.I))
    print("ФАКТ · НЕ чіпаю «%s»: %d збігів усередині слова — це %s, і межа слова їх зламала б" % (к, n, чому))
