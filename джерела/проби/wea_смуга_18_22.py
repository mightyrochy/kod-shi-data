# -*- coding: utf-8 -*-
"""П-5: смуга 18–22 °C — «1 шар + знімний». `python3 проби/wea_смуга_18_22.py`.

Смуга 18–26 стояла одним рядком «1 шар», і на +19 °C лічба шарів карала сукню з
кардиганом за «шарів забагато» (2 проти 1 — |брак| = 1, знахідка на кожному
такому образі), а слот верхнього шару мапа з пулу знімала. Проба друкує мапу й
знахідки K-WEA-01 на трьох образах у трьох температурах смуги."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import outfit as O, суд_погода as СП

сукня = dict(id="с-1", слот="сукня", hex="#334455", назва="Сукня", матеріал="віскоза", тип="сукня")
кардиган = dict(id="к-1", слот="верхній_шар", hex="#ddccbb", назва="Кардиган",
                матеріал="бавовна", тип="кардиган", тип_верхнього="кардиган")
жакет = dict(id="ж-1", слот="верхній_шар", hex="#223344", назва="Жакет unlined",
             матеріал="бавовна", тип="блейзер")
print("мапа: %s" % " · ".join("%g…%g → %g шар(и)" % (lo, hi, d["шари"])
                              for lo, hi, d in O.ТЕМП_МАПА if -9 <= lo <= 26))
for назва, речі in (("сукня сама", [сукня]), ("сукня + кардиган", [сукня, кардиган]),
                    ("сукня + жакет", [сукня, жакет])):
    рядок = []
    for т in (19.0, 21.0, 24.0):
        смуга = next((d for lo, hi, d in O.ТЕМП_МАПА if lo <= т < hi), None)
        E = O.елементи(речі, стан="надворі")
        зн = [z for z in СП.погода(E, темп_c=т, стан="надворі", речі=речі)
              if z["правило"] == "K-WEA-01" and "шарів" in z["суть"]]
        слот = "є" if смуга["шари"] > 1 else "знято"
        рядок.append("%+.0f°C мапа %g слот %-5s → %s"
                     % (т, смуга["шари"], слот,
                        "%s (сила_нп %s)" % (зн[0]["суть"], зн[0]["сила_нп"]) if зн else "тихо"))
    print("%-17s | %s" % (назва, "  |  ".join(рядок)))
