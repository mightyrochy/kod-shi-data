"""K-CRA-11 (клас команд розкладки — єдиний вихід нульових даних): перевірка цілого.
`python3 проби/cra_K-CRA-11.py`.

Зведення аудиту ставить правилу «ціле», і проба це стверджує, а не лагодить:
`accessory.команди_розкладки` віддає опції з компромісами, вони доїжджають полем
`канал_3` у виході `від_моделі`, і слід у `trace` пишеться. Правило працює КАНАЛОМ
3 (K-CHN-01): інструкція, що зробити з річчю, яку людина вже має, — вона не потребує
ні SKU, ні наявності, ні ціни."""
import sys, pathlib, json
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B

вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
хустка = next(c for c in кат.values() if c["слот"] == "шарф" and c.get("розмір_см"))
база = [next(c for c in кат.values() if c["слот"] == сл) for сл in ("сукня", "взуття", "сумка")]
ід = [c["id"] for c in база + [хустка]]
вд = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
к3 = вд.get("канал_3") or {}
опції = к3.get("опції") or []
print("канал_3: опцій %d, команд-знахідок %d" % (len(опції), len(к3.get("команди") or [])))
for о in опції:
    print("  · %s (%s) → місця: %s" % (о.get("річ", "")[:34], о.get("клас"),
                                       ", ".join(о.get("допустимі_місця") or [])))
    if о.get("ворота_формату"):
        print("      ворота формату:", о["ворота_формату"][:70])
assert опції, вд.get("канал_3")
assert any(о.get("клас") == "хустка/шарф" for о in опції), опції
print("K-CRA-11 ціле: образ = набір речей ПЛЮС набір команд, і команди виходять")
print("  навіть тоді, коли каталог не повернув нічого — каналу 3 SKU не потрібен")
