"""Рядок 89 (реєстр 5616, клас Г12): каталог у git брудний, і збірка чистить його ЩОРАЗУ на розпакованій копії.
Факт: числа брудності `чистка_каталогу._брудність` на сирому `каталог_повний.xml.gz` (помилки слота, подвійні
екранування, мовні двійники, лежалі назви) і скільки речей лишається після чистки й читання фіду.
Запуск: python3 джерела/проби/каталог_проблеми_г_брудність.py   (~1 хв)"""
import gzip, os, shutil, sys, tempfile                                         # noqa: E401
Д = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, Д); os.chdir(Д)                                             # noqa: E702
import чистка_каталогу as Ч, feed as F                                         # noqa: E401,E402
т = tempfile.mkdtemp(); сирий = os.path.join(т, "каталог_повний.xml")
with gzip.open(os.path.join(Д, "..", "каталог_повний.xml.gz"), "rb") as г, open(сирий, "wb") as в:
    shutil.copyfileobj(г, в)
сл, екр, дв, леж = Ч._брудність(сирий)
print("сирий каталог із git: помилок слота %d · подвійних екранувань %d · мовних двійників %d · лежалих назв %s" % (сл, екр, дв, леж))
чистий = os.path.join(т, "чистий.xml"); Ч.почистити(сирий, чистий)            # noqa: E702
print("після чистки: %s" % (Ч._брудність(чистий),))
оф = F.читати_yml(чистий)[0]
print("речей: у git %d → у фіді після чистки %d" % (open(сирий, encoding="utf-8").read().count("<offer "), len(оф)))
shutil.rmtree(т)
