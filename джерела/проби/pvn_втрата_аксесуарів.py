"""Рядок 150 · ремонт повноти не губить прикрас і сумки, про які його не просили.

До ремонту рука 2 має 4 прикраси різних сімей і 2 сумки (блокер «слот_двічі» просить
звести сумки до однієї). Відповідь ремонту — та, що прийшла на ноутбуці від gemma:
модель дописала верхній шар і переписала склад коротше, лишивши одну прикрасу й одну
сумку. Друкує лічбу прикрас і сумок ДО ремонту, у відповіді моделі (це й був склад
образу на main) і після `дотримати_склад`.
Запуск: cd джерела && python3 проби/pvn_втрата_аксесуарів.py"""
import sys; sys.path.insert(0, ".")
import повнота_образу as П
from пакет_моделі import номери_речей
from вердикт_моделі import номер_речі

РЕЧІ = [("в1", "верх", "Джемпер вовняний"), ("н1", "низ", "Штани шоколад"),
        ("вз1", "взуття", "Балетки замшеві"), ("с1", "сумка", "Сумка Sack"),
        ("с2", "сумка", "Клатч Rio"), ("п1", "прикраси", "Сережки золоті"),
        ("п2", "прикраси", "Намисто з перлин"), ("п3", "прикраси", "Браслет тонкий"),
        ("п4", "прикраси", "Каблучка з каменем"), ("вш1", "верхній_шар", "Півпальто")]
кандидати = {}
for ід, слот, назва in РЕЧІ:
    кандидати.setdefault(слот, []).append(dict(id="%s@к.ua" % ід, слот=слот, назва=назва))
ном = номери_речей(кандидати)[0]
словник = {r["id"]: r for рч in кандидати.values() for r in рч}
до = [r["id"] for r in словник.values() if r["слот"] != "верхній_шар"]
попередній = dict(образи=[dict(ід="о1", речі=[номер_речі(і, ном) for і in до],
                              структура=dict(ок=False, блокери=[dict(код="слот_двічі",
                                  речі=[номер_речі(і, ном) for і in ("с1@к.ua", "с2@к.ua")])]))])
відповідь = [[і for і in до if і in ("в1@к.ua", "н1@к.ua", "вз1@к.ua", "с1@к.ua", "п1@к.ua")]
             + ["вш1@к.ua"]]
після, повернуто = П.дотримати_склад(відповідь, попередній, ном, словник)
лічба = lambda склад: (sum(словник[і]["слот"] == "прикраси" for і in склад),
                       sum(словник[і]["слот"] == "сумка" for і in склад))
print("до ремонту:            прикрас %d · сумок %d · речей %d" % (*лічба(до), len(до)))
print("відповідь моделі (main): прикрас %d · сумок %d · речей %d" % (*лічба(відповідь[0]), len(відповідь[0])))
print("після дотримати_склад:   прикрас %d · сумок %d · речей %d" % (*лічба(після[0]), len(після[0])))
print("повернуто кодом:", ", ".join("%s (%s)" % (p["назва"], p["сім_я"]) for p in повернуто) or "—")
ок = лічба(після[0]) == (4, 1) and лічба(відповідь[0]) == (1, 1) and "вш1@к.ua" in після[0]
print("ВЕРДИКТ:", "ок — прикраси цілі, сумка зведена блокером, верхній шар ремонту лишився"
      if ок else "ПРОВАЛ")
sys.exit(0 if ок else 1)
