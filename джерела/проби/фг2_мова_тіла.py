"""Ф-2: чотири фрази §3 п.4 звіту Research (мова про ТІЛО без її мети) і той самий
гейт R-LNG-01 на АНГЛІЙСЬКОМУ боці — на словнику `внутрішня_мова.ЗАЯВИ`, з якого
мовна модель складає речення жінці. Друкує факт: скільки фраз лишилось у коді і
скільки заяв заявляють ефект на зоні тіла.
Запуск із теки `джерела`: `python3 проби/фг2_мова_тіла.py`."""
import sys, pathlib, re
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import language_gate as МГ, внутрішня_мова as ВМ

ДЖ = pathlib.Path(__file__).resolve().parent.parent
ФРАЗИ = (("силует_пропорції.py", r"ховає виражену талію\""),
         ("верхнє_стан.py", r"вертикаль біля шиї подовжує"),
         ("суд_силует.py", r"нога читається довгою"),
         ("внутрішня_мова.py", r"lengthens the neck"))
print("ФРАЗИ ПРО ТІЛО В КОДІ (лишок — рядки, які їдуть людині чи моделі):")
разом = 0
for файл, формула in ФРАЗИ:
    текст = (ДЖ / файл).read_text(encoding="utf-8")
    # рядки-коментарі не рахуються: провенанс правки цитує фразу, яку прибрано
    влучень = [р for р in текст.splitlines()
               if re.search(формула, р) and not р.lstrip().startswith("#")]
    разом += len(влучень)
    print("  %-24s %-32s → %d" % (файл, формула[:30], len(влучень)))
print("  РАЗОМ поза коментарями: %d" % разом)

в = МГ.перевірити_внутрішню_мову(ВМ.ЗАЯВИ)
print("\nR-LNG-01 НА СЛОВНИКУ ДЛЯ МОВНОЇ МОДЕЛІ: заяв %d · заявляють ефект на зоні тіла %d"
      % (в["усього"], len(в["брудні"])))
for д in в["брудні"][:8]:
    print("  %-46s %s" % (д["код"], д["збіги"][:2]))

пропущено = [т for т, ч in МГ._КЕЙСИ_EN if not ч and МГ.перевірити_внутрішню_мову({"к": т})["чисто"]]
хибно = [т for т, ч in МГ._КЕЙСИ_EN if ч and not МГ.перевірити_внутрішню_мову({"к": т})["чисто"]]
print("\nРОЗДІЛЬНІСТЬ англійського боку: кейсів %d · пропущено заборонених %d · "
      "хибно затавровано виміру %d" % (len(МГ._КЕЙСИ_EN), len(пропущено), len(хибно)))
for т in пропущено + хибно:
    print("  ✗", т[:70])
