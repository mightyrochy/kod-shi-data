"""K-WEA-05 (матеріал верху — погодні ворота): `python3 проби/wea_K-WEA-05.py`.

ЧОМУ БУЛО «БЕЗ СЛІДУ» НА ПОЛОВИНІ СЛОТІВ: емітент читав `матеріал_верху or
тканина`. `матеріал_верху` пише `feed._взуттєві_поля` і ЛИШЕ для взуття (1 508 із
8 975), ключа `тканина` запис каталогу не має зовсім (0). Отже замшева СУМКА в
мокрий сніг не діставала умови жодного разу — 0 із 453 сумок каталогу, — хоч
тема-10 XXIX.2 називає її дослівно: «замша — вето, як у взутті».
ЩО ПОКАЗУЄ ПРОБА: сумка з замші в мокрий сніг дає рядок K-WEA-05 з УМОВОЮ
(просочити), а не з вето; у суху погоду того самого рядка нема."""
import sys, pathlib, json
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import feed as Ф, bridge as B, accessory as АК

вх = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml"); вх["гілка"] = 0
вх["сценарій"].update(темп_c=-3, опади="мокрий_сніг", вітер=5)
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
мат = lambda c: (c.get("матеріал_верху") or c.get("волокно") or c.get("матеріал") or "").lower()
сум = [c for c in кат if c.get("слот") == "сумка"
       and any(v in мат(c) for v in АК.ВОЛОГА_ВІДМОВА)]
print("сумок із матеріалом відмови у каталозі пакета:", len(сум), "(було 0: поле не читалось)")
ціль = сум[0]
решта = [next(c["id"] for c in кат if c.get("слот") == сл) for сл in ("сукня", "взуття")]
def _рем(z):
    р = z.get("ремонти") or z.get("ремонт") or []
    return (р[0] if isinstance(р, list) and р else р if isinstance(р, str) else "")
print("сумка:", ціль["назва"][:46], "· матеріал «%s»" % мат(ціль))
for підпис, опади in (("мокрий_сніг", "мокрий_сніг"), ("без опадів", "ні")):
    вх["сценарій"]["опади"] = опади
    вм = json.loads(B.виклик("від_моделі", json.dumps(
        dict(вх, ід=[ціль["id"]] + решта), ensure_ascii=False)))
    о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
    з = [z for z in (о.get("знахідки") or [])
         if z.get("правило") == "K-WEA-05"
         and {ціль["id"], ціль.get("назва")} & set(z.get("речі") or [])]
    print("%-12s K-WEA-05 на сумці:" % підпис, "НЕМА" if not з else
          "%s %.2f · %s · ремонт: %s" % (з[0]["сила"], з[0]["сила_нп"],
                                         з[0]["суть"][:40], (_рем(з[0]) or "—")[:38]))
