"""K-CRA-06 (глибина шарування) на живому шляху: `python3 проби/cra_K-CRA-06.py`.

ЧОМУ СЛІДУ НЕ БУЛО: емітента не існувало взагалі, тож пункт 8 чекліста надлишку
(«видимих шарів ≤3») стояв «пройдено» на БУДЬ-ЯКОМУ образі — провал може поставити
лише знахідка. Правило має три твердження; вхід на живому каталозі є у двох:
стеля видимих шарів (слоти є завжди) і градація довжин (`довжина_рівень` мають
534 із 3 121 «верх» і 209 із 764 «верхній_шар»). Товщини виробу фід не несе жодним
полем, і третє твердження чесно не реалізоване."""
import sys, pathlib, json, collections
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B

вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["гілка"] = 0
вх["сценарій"] = dict(вх["сценарій"], темп_c=2, опади="ні")
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
рівні = collections.Counter((c["слот"], c["довжина_рівень"]) for c in кат.values()
                            if c["слот"] in ("верх", "верхній_шар") and c.get("довжина_рівень"))
спільні = sorted({v for (s, v) in рівні
                  if ("верх", v) in рівні and ("верхній_шар", v) in рівні})
print("рівні довжини, спільні для «верх» і «верхній_шар»:", спільні)
рів = спільні[0]
# річ береться з КАТАЛОГУ пакета, не лише з пулу: потрібна ПАРА шарів з однаковим
# рівнем, і `перевірити_від_моделі` законно судить річ поза кандидатами.
пара = [next(c for c in кат.values() if c["слот"] == сл and c.get("довжина_рівень") == рів)
        for сл in ("верх", "верхній_шар")]
решта = [next(c for c in кат.values() if c["слот"] == сл) for сл in ("низ", "взуття")]
ід = [c["id"] for c in пара + решта]
print("образ:", [(кат[i]["слот"], кат[i].get("довжина_рівень")) for i in ід])
вд = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
о = ((вд.get("вердикт") or {}).get("образи") or [{}])[0]
з = next((z for z in (о.get("знахідки") or []) if z["правило"] == "K-CRA-06"), None)
print("K-CRA-06 у вердикті:", "НЕМА" if not з else
      "%s %.2f · %s" % (з["сила"], з["сила_нп"], з["суть"][:62]))
print("  речі рядка:", (з or {}).get("речі"), "· регістр", (з or {}).get("регістр"))
провал = ((о.get("чекліст") or {}).get("надлишок") or {}).get("провал") or []
print("пункт 8 чекліста:", "провал" if any("глибина шарування" in p for p in провал) else провал)
assert з, о.get("знахідки")
