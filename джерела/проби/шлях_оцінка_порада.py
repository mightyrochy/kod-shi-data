"""Ділянка 8 → Ч-4: ЧОМУ ПОРАДА ПРО МАКІЯЖ І ПОМАДУ. Доти `_стан_для_поради` ставив `фото=True` за
словом «фото» в її словах (регулярка `_ПОДІЯ_ФОТО`), а підпис `[фото ф1]` ставить сам показ — тож будь-яка
репліка з фото ставала «вечором» із темами «мета» й «макіяж». З Ч-4 «її фотографуватимуть» — код шару
`activity: photoshoot`; її слова код не читає. Міряє теми поради на картку з запису 26.09.
Запуск із `джерела`: python3 проби/шлях_оцінка_порада.py"""
import sys, re; sys.path.insert(0, '.')
import паспорт_нагоди as ПН
print("регулярка «фото» в її словах: %s" % ("Є" if hasattr(ПН, "_ПОДІЯ_ФОТО") else "нема (Ч-4)"))
ПОКАЗ = open('показ.html', encoding='utf-8').read()
print('показ.html:%d — підпис фото в тексті репліки: %s'
      % (ПОКАЗ[:ПОКАЗ.index("return '[фото ' + фото")].count('\n') + 1, "'[фото ' + фото.join(', ') + '] '"))
КАРТКА = dict(нагода=None, місце='зал', година=11, темп_c=18)     # картка з запису, типові значення
ПАСП = dict(джерело_полів={'нагода': ПН.ТИПОВА_НАГОДА_РЕЧІ}, нагода='щоденне')
ХОДИ = [('хід 1, її слова без «фото»', 'Мене цікавить чи поєднуються ці кольори між собою і чи підійдуть вони мені?'),
        ('хід 1, як його бачить код', '[фото ф1] Мене цікавить чи поєднуються ці кольори між собою і чи підійдуть вони мені?')]
for підпис, слова in ХОДИ:
    ст = ПН._стан_для_поради(КАРТКА, ПАСП, слова)
    п = ПН.порада_коду(КАРТКА, ПАСП, слова, є_річ=True)
    print('%-30s → фото=%-5s теми: %s' % (підпис, ст['фото'], ', '.join((п or {}).get('теми') or ['—'])))
ф = ПН.порада_коду(КАРТКА, dict(ПАСП, активність="фотосесія"), "", є_річ=True)
print('%-30s → теми: %s' % ('шар: activity=photoshoot', ', '.join((ф or {}).get('теми') or ['—'])))
дані, ходів, усі = [], 0, []
while ходів < 6:
    п = ПН.порада_коду(КАРТКА, dict(ПАСП, поради_дані=list(дані)), ХОДИ[1][1], є_річ=True)
    if not п: break
    ходів += 1; усі += п['теми']; дані += п['теми']
print('скільки ходів поспіль код проситиме відповісти, поки вона лише просить оцінити образ: %d'
      ' (теми: %s)' % (ходів, ', '.join(усі)))
print('→ «мета» й «макіяж» — лише коли вечір названо (година, нагода, місце) чи шар сказав photoshoot;'
      ' підпис показу «[фото …]» тем не будить.')
