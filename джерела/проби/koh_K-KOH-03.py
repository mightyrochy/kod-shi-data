# -*- coding: utf-8 -*-
"""K-KOH-03 (high-low: один свідомий розрив): `python3 проби/koh_K-KOH-03.py`.

ЧОМУ БУЛО «ЛИШЕ СЛІД»: правило МІНЯЄ вердикт — множник ×0.6 на силу K-KOH-02 і є
твердженням «один свідомий розрив законний», — але його ID жив лише в лозі й у
тексті ремонту. Окремої знахідки воно не дістає навмисно: вимір один (розкид
формальності), і другий рядок із того самого числа був би дублем кодів.
ЩО ЩЕ ПОЛАГОДЖЕНО: ремонт пропонував «лишити як свідомий high-low» ЗАВЖДИ —
зокрема й у буденній нагоді, де та сама гілка коду щойно відмовилась зарахувати
полегшення (`престиж is False`). Корпус каже протилежне: «high-low is not offered
by default. It is offered only when the scenario carries a legible
prestige/creative marker».
ЩО ПОКАЗУЄ ПРОБА: код K-KOH-03 їде полем `також_правила` на рядку K-KOH-02, і
другий ремонт міняється разом із контекстом."""
import sys, pathlib, json
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import feed as Ф, bridge as B

вх = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml"); вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
за_тип = {}
for c in кат: за_тип.setdefault(c.get("тип"), []).append(c)
# «спортивний» (рівень 1–3) + «клатч» (8–8) + взуття: розкид 5 — понад ОБИДВА
# допуски (престижний 2 і буденний 1), тож рядок виходить в обох контекстах і
# різниця між ними видна в РЕМОНТІ, а не в наявності знахідки
іди = [за_тип[t][0]["id"] for t in ("спортивний", "клатч", "човники") if за_тип.get(t)]
print("образ: спортивна сукня (рівень 1–3) + клатч (8–8) + човники (6–8)")
for підпис, сцен in (("буденна нагода (престижу нема)",
                      dict(нагода="прогулянка", місце="парк", дрес_код="")),
                     ("робота (престиж є)", dict(нагода="робота"))):
    в = json.loads(json.dumps(вх, ensure_ascii=False)); в["сценарій"].update(сцен)
    вм = json.loads(B.виклик("від_моделі", json.dumps(dict(в, ід=іди), ensure_ascii=False)))
    о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
    з = next((z for z in (о.get("знахідки") or []) if z["правило"] == "K-KOH-02"), None)
    print("%-32s" % підпис, "K-KOH-02 нема" if not з else
          "сила %.2f · також_правила=%s" % (з["сила_нп"], з.get("також_правила")))
    if з:
        print("      ремонт:", str(з.get("ремонт"))[:150])
