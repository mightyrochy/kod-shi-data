def сирі(*шаблони):
    """[(ім'я, промпт)] з `аудит/тести/сирі_2026-09-25` і `сирі_2026-09-26` (коли є)."""
    вих = []
    for д in ("сирі_2026-09-25", "сирі_2026-09-26"):
        for ш in шаблони:
            for ф in sorted(glob.glob(os.path.join(К, "..", "аудит", "тести", д, "**", ш), recursive=True)):
                с = (gzip.open if ф.endswith(".gz") else open)(ф, "rt", encoding="utf-8").read()
                if "── ПРОМПТ" in с:
                    вих.append((re.sub(r"_(ПАКЕТ|ВЕРДИКТ|ОПИС)_V1.*$", "", os.path.relpath(ф, os.path.join(К, "..", "аудит", "тести", д))),
                                с.split("\n", 1)[1].split("\n── ВІДПОВІДЬ")[0].strip()))
    return вих


def осі(зона):
    """Речення `graph.зона_словами` → осі речі тим самим кодом, що дає продукт (`дріт_моделі.осі`)."""
    з = {}
    м = re.search(r"світлота (\d+)–(\d+) \(([^)]*)\)", зона or "")
    if м:
        з["колір"] = dict(L=(float(м.group(1)), float(м.group(2))), джерело=м.group(3),
                          розкид=(None if "без виміряного" in м.group(3) else 1.0))
    м = re.search(r"край (\d+)–(\d+) см від підлоги \(([^)]*)\)", зона or "")
    if м:
        з["край"] = dict(см=(float(м.group(1)), float(м.group(2))), джерело=м.group(3))
    м = re.search(r"форм\. (\d+)–(\d+)", зона or "")
    if м:
        з["формальність"] = dict(інтервал=(float(м.group(1)), float(м.group(2))))
    м = re.search(r"тканина на (?:(-?\d+)–(-?\d+)|від (-?\d+)) °C", зона or "")
    if м:
        з["сезон"] = dict(смуга=((float(м.group(1)), float(м.group(2))) if м.group(1) else (float(м.group(3)), 999)))
    return Д.осі(з)


