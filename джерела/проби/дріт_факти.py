def з_осями(x):
    """Копія даних, де кожна річ несе «осі» (зона числами й каблук кодом) — так її несе пул продукту."""
    if isinstance(x, dict):
        в = {к: з_осями(v) for к, v in x.items()}
        if x.get("н") and (isinstance(x.get("зона"), str) or x.get("каблук")):
            о = в["осі"] = осі(x.get("зона") or "")
            т = str(x.get("каблук") or "")
            if т:
                о["heel"] = КАБЛУК.get(т, "yes")
                о.update({к: Д._КАБЛУК_ФОРМА[w] for к, w in (("heel_shape", "тонкий"), ("heel_shape", "товстий")) if w in т})
                о.update({к: Д._КАБЛУК_ВИСОТА[w] for к, w in (("heel_height", "високий"), ("heel_height", "низький")) if w in т})
        return в
    return [з_осями(v) for v in x] if isinstance(x, list) else x


def _коди(v):
    """Слово ядра → усі його коди: таблиці внутрішньої мови й закриті переліки `дріт_моделі`."""
    к = {v, v.replace(" ", "_"), Д._дрес_код(v), Д.реєстр(v), Д.колір_код(v)[0]}
    for т in ВМ.ТАБЛИЦЯ.values():
        к |= {код for код, ключ in т.items() if ключ in (v, v.replace(" ", "_"), v + "_без_уточнення")}
    for ім in dir(Д):
        м = getattr(Д, ім)
        if ім.startswith("_") and isinstance(м, dict) and isinstance(м.get(v), str):
            к.add(м[v])
    return к | {м[v] for м in П.ЗНАЧЕННЯ_ВІДПОВІДІ_EN.values() if v in м}


_КОД_ЧОМУ = {ч: к for к, ч in __import__("суд_від_моделі")._ЧОМУ_БЛОКЕРА.items()}


def вимоги_даними(вимоги):
    """Факти, що в ремонті стояли реченнями `завдання.вимоги`: неповні образи
    [(ід образу, код блокера)] («Неповні образи: …», «ПОВНОТА ОБРАЗУ …», «Адресно: …») і слот розриву."""
    пари, розрив = [], None
    for р in вимоги or []:
        if re.search(r"^(Неповні образи|ПОВНОТА ОБРАЗУ|Адресно)", р):
            for ід, чому in re.findall(r"((?:о\d+(?:, )?)+) — ([^;]+?)(?=;|\. |\.$|$)", р.split(":", 1)[1]):
                пари += [(і, _КОД_ЧОМУ[ч.strip()]) for і in ід.split(", ") for ч in чому.split(" / ") if ч.strip() in _КОД_ЧОМУ]
        м = re.search(r"ламати палітру\D*?«([^»]+)»", р, re.I)
        розрив = м.group(1) if м else розрив
    return пари, розрив


