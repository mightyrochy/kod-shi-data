# -*- coding: utf-8 -*-
"""Рядок 1984 (1): `злити` після `--ліміт 5` на brenda — скільки придатних записів лишається. Каталог збагачення справжній."""
import gzip, json, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "zhnyvarka"))
import перезняти_збагачення as П, feed as F
усе = json.loads(gzip.open(os.path.join(П.ДЖЕРЕЛА, "каталог_збагачення.json.gz")).read())
суф = "@brenda.ua"
каталог = {o["id"] for o in F.читати_yml(F.каталог_на_диску("каталог_повний.xml"))[0]}
брен = [к for к in усе if к.endswith(суф)]
пр = lambda d: sum(1 for к in брен if F._збагачення_придатне(d[к]))
вибірка = [к for к in брен if F._збагачення_придатне(усе[к])][:5]
# перезйомка 5 речей: 4 вдались, 1 — помилка на ТОМУ САМОМУ кадрі
нове = {к: dict(усе[к], прогін="x") for к in вибірка[:4]}
нове[вибірка[4]] = П._помилка("збій моделі", усе[вибірка[4]]["фото"], "m")
до = dict(усе)
for к in брен:                          # СТАРА поведінка: усе поза вибіркою — помилка
    до[к] = нове.get(к) or П._помилка("речі нема в почищеному каталозі")
після = dict(усе)
П.злити_записи(після, нове, суф, каталог)
print("brenda: записів %d, придатних зараз %d, у каталозі %d" % (len(брен), пр(усе), len(каталог & set(брен))))
print("ДО  злиття (--ліміт 5): придатних %d" % пр(до))
print("ПІСЛЯ злиття (--ліміт 5): придатних %d; кадр невдалої речі зберіг запис: %s" % (пр(після), F._збагачення_придатне(після[вибірка[4]])))
