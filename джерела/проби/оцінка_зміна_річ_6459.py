# -*- coding: utf-8 -*-
"""Рядок 6459: «Що змінити» — пари «текст на картці ↔ річ під ним», де текст називає річ іншого виду тієї самої групи
(взуття, низ, верх), ніж річ під ним і її річ, яку зміна міняє, або лише речі чужої групи (основи слів — для лічби
проби, продукт слів не читає). ДО — переклади записів; ПІСЛЯ — ті самі пари, що лишає
`прийняти_оцінку` (звірка цілі зміни ідами); переклад тексту наново тут не жене — його міряє живий прогін.
Запуск із `джерела`: python3 -W ignore проби/оцінка_зміна_річ_6459.py <тека записів>"""
import json, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from оцінка_картка_6452 import записи, суд_з_промпту, О

ОСНОВИ = {"boots": "чобо|чобі|казак|казач", "ankle_boots": "ботильйон|черевик|челсі|ботинк|ботик",
          "loafers": "лофер", "shoes": "туфл", "sandals": "босоніж|сандал", "skirt": "спідниц|юбк",
          "trousers": "штан|брюк", "jeans": "джинс",
          "top": "топ|верх|блуз|джемпер|светр|кофт"}
ГРУПА = {**dict.fromkeys(("boots", "ankle_boots", "loafers", "shoes", "sandals"), "взуття"),
         **dict.fromkeys(("skirt", "trousers", "jeans"), "низ"), "top": "верх"}
РОДИНА = {"chelsea_boots": "ankle_boots", "blouse": "top", "sweater": "top", "knitwear": "top", "top_garment": "top",
          "pumps": "shoes", "heeled_sandals": "sandals"}


def пари(п, зміни, вх, вих):
    """[(ід зміни, вид речі, текст картки)] для перевірених змін (`зміни` — записи відповіді)."""
    своя = {р["id"]: р.get("kind") for р in п["items"]}
    за_ід = {с["id"]: с for с in п.get("changes") or []}
    н_тексту = {" ".join(т.split()): н for н, т in вх.items()}
    for з in зміни:
        с = за_ід.get(О.ід_на_дріт(з["id"]))
        if с:
            вид = (с.get("with_shop") or {}).get("kind") or своя.get(с.get("with_own"))
            можна = {РОДИНА.get(в, в) for в in (вид, своя.get(с["replace"][0]))}
            yield з["id"], вид, можна, вих.get(н_тексту.get(" ".join(str(з.get("text") or "").split())), "")


if __name__ == "__main__":
    до, після = [], []
    for сц, ім, п, об, вх, вих in записи(sys.argv[1]):
        картка = О.прийняти_оцінку(json.dumps(об), суд_з_промпту(п))["картка"] or {}
        лишились = {з["ід"] for з in картка.get("змінити", [])}
        for ід, вид, можна, текст in пари(п, (об or {}).get("change") or [], вх, вих):
            назване = {р for р, о in ОСНОВИ.items() if re.search(о, текст.lower())}
            групи = {ГРУПА.get(р) for р in можна}
            своєї = {р for р in назване if ГРУПА[р] in групи}
            if своєї - можна or (not своєї and назване):
                рядок = "%s %s %s (%s) «%s»" % (сц, ім, ід, вид, текст[:70])
                до.append(рядок)
                if О.ід_з_дроту(ід) in лишились:
                    після.append(рядок)
    print("пар «текст ↔ річ» з іншим видом: ДО %d · ПІСЛЯ (код) %d" % (len(до), len(після)))
    print("\n".join("  " + р + ("  ← лишається" if р in після else "") for р in до))
