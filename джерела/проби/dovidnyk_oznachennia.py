"""Проба довідника правил (рядок 1997): означення, змішані блоки, «поза корпусом».
Друкує факти; git не кличе (розділ правок міряє сам `правила.py`).
Прогін: cd джерела && python3 проби/dovidnyk_oznachennia.py"""
import os, sys
_ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(_ТУТ, ".."))
import ід_правил as ІП, корпус as КР, gate_reach as ГД, правила as П

корп = sorted(КР.ід())
форм = П.формулювання()
без = [i for i in корп if i not in форм]
print("ID у корпусі %d · з формулюванням %d · названо, не означено %d"
      % (len(корп), len(корп) - len(без), len(без)))
print("  названо, не означено:", ", ".join(без))
форми = {}
for імя, t in КР.текст().items():
    for я in П._якорі(t):
        форми[я[2]] = форми.get(я[2], 0) + 1
print("якорі за формою:", ", ".join("%s %d" % (k, v) for k, v in sorted(форми.items())))
# змішаний блок: у тексті блоку ID стоїть початок формулювання ІНШОГО ID (ковтнутий сусід)
ковтнуто = sorted((i, x) for i, (_, бл) in форм.items() for x, (_, бл2) in форм.items()
                  if x != i and len(бл2) >= 40 and бл2[:40] in бл)
три = sorted(i for i, (_, бл) in форм.items() if len(ІП.бази_в_тексті(бл) - {i}) >= 3)
print("блоків, що ковтнули означення сусіда: %d %s" % (len(ковтнуто), ковтнуто[:5]))
print("блоків із ≥3 чужими ID (згадки, не означення): %d  %s" % (len(три), три))
код = ГД.з_коду(os.path.join(_ТУТ, ".."))
print("ID, які код цитує поза корпусом: %d" % len(set(код) - set(корп)))
