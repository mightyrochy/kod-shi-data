# -*- coding: utf-8 -*-
"""Проба (рядок 226): ЧИ БАЧИТЬ КОД РОЖЕВЕ ЗОЛОТО — скільки ювелірних речей дістає вимір
частки металу, скільки нулів лишається і що читає третє вікно `palettes.РОЖЕВЕ_ЗОЛОТО`.
Друкує факт, моделі не кличе. Запуск: python3 джерела/проби/рожеве_золото_226.py"""
import collections, os, sys                                                   # noqa: E401
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import colorspace as cs, palettes as ПЛ, фід_каталог as ФК, фід_збагачення as ФЗ  # noqa: E401,E402
записи = ФК._прочитати_каталог(ФК.каталог_на_диску(), ліміт_фото=0)["каталог"]
c, зб = collections.Counter(), ФЗ.читати_збагачення()
for r in записи:
    сл, м, ч = r.get("слот"), r.get("метал"), r.get("частка_металу")
    if not м or сл not in ПЛ.СЛОТИ_МЕТАЛУ:
        continue
    c["ювелірних_з_металом"] += 1
    c["без_входу" if ч is None else ("нуль" if ч == 0 else "частка>0")] += 1
    if м == "рожеве_золото":
        c["названо_рожевим"] += 1
        c["названо_рожевим_вхід_є"] += int(ч is not None)
    з = зб.get(r.get("id")) or {}
    к = з.get("колір_основний") or {}
    if к.get("hex") and ПЛ.метал_речі(cs.hx(к["hex"]), сл) == "рожеве_золото":
        c["кластер_у_вікні_рожевого"] += 1
print("ювелірних із названим металом %d · вимір частки: >0 у %d, нуль у %d, входу нема в %d"
      % (c["ювелірних_з_металом"], c["частка>0"], c["нуль"], c["без_входу"]))
print("названо рожевим золотом %d (вхід є у %d) · кластерів збагачення у вікні рожевого %d"
      % (c["названо_рожевим"], c["названо_рожевим_вхід_є"], c["кластер_у_вікні_рожевого"]))
# ВІКНА НЕ ПЕРЕТИНАЮТЬСЯ: жовте золото й срібло відповідають першими, рожеве — лише там,
# де доти було «не метал»; тому жодна стара відповідь не змінилась (тест нижче — на фактах)
for hex_, чек in (("#dcaf8b", "рожеве_золото"),   # ж-11653, кластер 52 % площі, тон 65°
                  ("#d4a373", "рожеве_золото"),   # мідний 585 на теплому кадрі, 69°
                  ("#cbb26a", "золото"),          # жовте золото на кадрі, 91° — вікно ЗОЛОТА
                  ("#c0c0c0", "срібло")):         # ахромат — вікно СРІБЛА
    м = ПЛ.метал_речі(cs.hx(hex_), "каблучка")
    print("%s → %s (LCh %s)%s" % (hex_, м, [round(x, 1) for x in cs.lch(cs.hx(hex_))],
                                  "" if м == чек else "  ← ЧЕКАЛИ %s" % чек))
    assert м == чек, hex_
print("поза ювелірним слотом вікно мовчить: %s" % ПЛ.метал_речі(cs.hx("#dcaf8b"), "верх"))
assert ПЛ.метал_речі(cs.hx("#dcaf8b"), "верх") is None
