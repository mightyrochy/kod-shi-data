# -*- coding: utf-8 -*-
"""Реєстр А (рядок 5630), клас А8: роздільність кадру. Розмір читається лише з адреси (Хорошоп,
WordPress, OpenCart зашивають його в шлях); у решти крамниць він невідомий без мережі. Друкує:
у скількох речах перший кадр картки має розмір в адресі, скільки з них менші за 400×600 і 250 px
по більшій стороні, скільки речей мають у фіді одне фото чи жодного і по крамницях — малі кадри.
Запуск: cd джерела && python3 проби/каталог_проблеми_а_роздільність.py"""
import collections, os, sys, re
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed as Ф, фід_фото as ФФ
оф = Ф.читати_yml(Ф.каталог_на_диску("каталог_повний.xml"))[0]
зб, сп, хо = Ф.читати_збагачення(), ФФ.спільні_фото(оф), ФФ.хости_крамниць(оф)
c, малі = collections.Counter(), collections.Counter()
for o in оф:
    з, м = зб.get(o["id"]), o.get("магазин")
    р = ФФ.кадри_речі(o, сп.get(м) or {}, хо, з.get("фото") if isinstance(з, dict) else None)
    c["фото у фіді: %s" % ("0", "1", "≥2")[min(len(o.get("фото") or []), 2)]] += 1
    if not р:
        continue
    п = ФФ.площа_фото(р[0])
    if п is None:
        c["розмір першого кадру невідомий"] += 1; continue
    c["розмір першого кадру відомий"] += 1
    if п < 400 * 600:
        c["менший за 400×600"] += 1; малі[м] += 1
    ч = re.findall(r"(\d{2,4})x(\d{2,4})", р[0])
    c["менший за 250 px"] += bool(ч and max(map(int, ч[-1])) < 250)
for к, н in sorted(c.items()):
    print("  %-34s %d" % (к, н))
print("малі перші кадри по крамницях:", малі.most_common(8))
