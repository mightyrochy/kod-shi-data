"""М-2, знахідка Р-1 (#373): ЧИ ДОЇЖДЖАЮТЬ ДО КОДУ ЇЇ РЕЧІ, НАЗВАНІ ОДНИМ ЗАПИСОМ. У прогоні для
звіту 26.09 MamayLM віддала «спідницю і чоботи» однією own_items-річчю зі `slot: ["bottom",
"shoes"]`; сторож цитату прийняв, а шов не довіз жодної речі. Проба бере ту саму сиру відповідь
(`аудит/тести/сирі_2026-09-26/vidpovidi_n1_kontsert_gemma_s3.tar.gz`, seed3_01) і веде її шляхом
продукту: `прийняти_вхід` → `_її_речі` (клаузи ядра) → `паспорт_з_шару` (її речі в паспорті, без
фото). Друкує слот речі у внутрішній мові, клаузи і закріплені речі паспорта; окремо — `_її_речі`
на тій самій речі напряму. Та сама проба на main і на гілці.
Запуск із `джерела`: python3 проби/шлях_шар_її_речі.py"""
import sys, os, re, tarfile, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import мовний_шар as МШ

with tarfile.open("../аудит/тести/сирі_2026-09-26/vidpovidi_n1_kontsert_gemma_s3.tar.gz") as т:
    ч = next(ч for ч in т.getmembers() if ч.name.endswith("seed3_01_мовний_шар_вхід.txt"))
    с = т.extractfile(ч).read().decode("utf-8")
слова = re.split(r"\n\n(?:КОНТЕКСТ:|── ВІДПОВІДЬ)", с.split("\nСЛОВА:\n", 1)[1])[0].strip()
сире = с.split("── ВІДПОВІДЬ", 1)[1].split("──\n", 1)[1]
р = МШ.прийняти_вхід("scenario", сире)
вн = р["внутрішня"]
print("її слова: «%s»" % слова)
print("її речі у внутрішній мові: %s · незнайомі: %s" % (
    json.dumps([{к: x for к, x in о.items() if к in ("name", "slot", "status")} for о in вн.get("own_items") or []],
               ensure_ascii=False), [н for н in р["незнайомі"] if "own_items" in н] or "—"))
кл = МШ._її_речі(вн.get("own_items"))
print("клаузи ядра (`_її_речі`): %d %s" % (len(кл), [(к["слот"], к["назва"]) for к in кл]))
п = МШ.паспорт_з_шару(вн, {}, None, None, слова_ходу=слова)
пс = п["паспорт"]
print("закріплені її речі в паспорті: %s · відкинув сторож: %s" % (
    [(x.get("слот"), x.get("назва")) for x in пс.get("речі_з_фото") or [] if x.get("закріплена")],
    [в.split(" · ")[2] for в in п["вигадки"]] or "—"))
пряма = {"name": {"free_text": "спідницю і чоботи", "lang": "uk"}, "slot": ["bottom", "shoes"], "status": "has",
         "quote": "Збери образ під цю спідницю і чоботи"}
print("`_її_речі` напряму на річ зі slot списком: %d клаузи %s"
      % (len(МШ._її_речі([пряма])), [к["слот"] for к in МШ._її_речі([пряма])]))
