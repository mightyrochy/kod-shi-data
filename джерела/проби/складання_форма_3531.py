"""Рядки 3531, 3540: відповіді складання й ремонту, де образи лежать під ключами «OUTFITS_V1…V5» (списки без «]»)
чи в обгортці «answer» поруч з «version», «needed»: [] і луною вердикта. Та сама `відповідь_сира` кожного виклику
OUTFITS_V1 крізь `протокол.розбір_за_схемою`: ДО — з вимкненими трьома прочитаннями (список перед ключем-сусідом,
версія й порожні поля поруч з «answer», образи з ключів-імен схеми), ПІСЛЯ — як є: образів і ходів «свідомо» з ід.
Прогін: git archive origin/claude/zhyvi-13 аудит/живі_13 | tar x -C /tmp/z13 &&
  cd джерела && python3 проби/складання_форма_3531.py /tmp/z13/аудит/живі_13/*/*/вердикти.txt"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import протокол as П
НОВЕ = dict(_ключі_сусіди=П._ключі_сусіди, _поле_без_змісту=П._поле_без_змісту,
            _образи_з_ключів_схеми=П._образи_з_ключів_схеми)
ДО = dict(_ключі_сусіди=lambda а, б: False, _поле_без_змісту=lambda к, v: False,
          _образи_з_ключів_схеми=lambda об, нотатки: об)


def прочитати(сира, як):
    for ім, ф in як.items():
        setattr(П, ім, ф)
    об = П.розбір_за_схемою(сира, "ОБРАЗИ_V1")[0]
    обр = [о for о in (об or {}).get("образи") or [] if isinstance(о, dict)]
    return len(обр), sum(1 for о in обр for х in о.get("свідомо") or [] if х.get("знахідка"))


сума = [0, 0, 0, 0, 0]
for ф in sys.argv[1:]:
    for п in json.load(open(ф)).get("прогони") or []:
        for в in п.get("вердикти") or []:
            for вк in (в.get("етапи") or {}).get("виклики") or []:
                if '"answer":"OUTFITS_V1"' in re.sub(r"\s", "", str((вк.get("запит") or {}).get("текст") or "")):
                    до, після = прочитати(вк.get("відповідь_сира") or "", ДО), прочитати(вк.get("відповідь_сира") or "", НОВЕ)
                    сума = [сума[0] + 1] + [а + б for а, б in zip(сума[1:], до + після)]
                    if до != після:
                        print("%-28s рука %s %-8s ДО образів %d, ходів з ід %d → ПІСЛЯ образів %d, ходів з ід %d"
                              % ((ф.split("/")[-2][:28], в.get("рука"), вк.get("крок")) + до + після))
print("викликів OUTFITS_V1 %d · образів ДО %d → ПІСЛЯ %d · ходів з ід ДО %d → ПІСЛЯ %d"
      % (сума[0], сума[1], сума[3], сума[2], сума[4]))
