# -*- coding: utf-8 -*-
"""Перейменований образ ремонту зберігає адресу й день своєї пари через живий міст."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(sys.path[0])
import bridge as Б

вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")),
          сценарій=dict(нагода="побачення", місце="ресторан", година=19, темп_c=5),
          випадок="побачення, ресторан, 19:00", варіантів=2, мова_тексту="English", без_фото=1)
if len(sys.argv) > 1: вх["каталог"] = sys.argv[1]
виклик = lambda дія, **д: json.loads(Б.виклик(дія, json.dumps(dict(вх, **д), ensure_ascii=False)))
пул = виклик("запити")["пакети"]["1"]["пул"]
склад = lambda к: [пул[с][к % len(пул[с])]["н"] for с in ("сукня", "взуття", "сумка")]
перший = dict(образи=[dict(ід="о1", речі=склад(0), день="first day"),
                     dict(ід="о2", речі=склад(1), день="second day")])
до = виклик("від_моделі", ітерація=2, текст_моделі=json.dumps(перший, ensure_ascii=False))["вердикт"]
ціль = до["образи"][1]
ремонт = dict(образи=[dict(ід="перейменований", речі=ціль["речі"])])
після = виклик("від_моделі", ітерація=2, спроба_повноти=1, попередній_вердикт=до,
                текст_моделі=json.dumps(ремонт, ensure_ascii=False))
факт = після["вердикт"]["образи"][0]
ок = факт["ід"] == ціль["ід"] and факт.get("день") == ціль.get("день")
print("пара до ремонту:", ціль["ід"], ціль.get("день"))
print("перейменована відповідь:", факт["ід"], факт.get("день"), "· адреса й день збережені:", ок)
поп = dict(до, образи=[dict(до["образи"][0], речі=ціль["речі"]), ціль])
обидва = dict(образи=[dict(ід=о["ід"], речі=о["речі"]) for о in reversed(поп["образи"])])
дубль = виклик("від_моделі", ітерація=2, спроба_повноти=1, попередній_вердикт=поп,
               текст_моделі=json.dumps(обидва, ensure_ascii=False))["вердикт"]["образи"]
адреси = [(о["ід"], о.get("день")) for о in дубль]
очік = [(о["ід"], о.get("день")) for о in reversed(поп["образи"])]
ок = ок and адреси == очік
print("однаковий склад, різні адреси й дні:", адреси, "· очікувано:", очік, "·", адреси == очік)
sys.exit(not ок)
