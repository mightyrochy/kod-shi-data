# -*- coding: utf-8 -*-
"""Рядок 62: та сама річ каталогу в картках рук 1 і 2 одного прогону.

Тим самим шляхом, що показ (`запити` → `від_моделі`), синтетичною моделлю
стенда «пул[слот][i % довжина]». Друкує повтори id між картками і чи є знахідка
`k_var_01_прогону`. `K=1` — штучно звужений пул: розводити нічим, і тоді повтор
мусить бути НАЗВАНИЙ, а слоти лишитись непорожніми.
Прогін: python3 проби/povtor_ruk_62.py
"""
import sys, os, json
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import bridge as B

СЛОТИ = ("сукня", "верх", "низ", "взуття", "сумка", "пояс", "прикраси")
ЯКИЙ = 1                      # стенд бере образ №1 (`образи[0]` у `ВИБІР_V1`)
база = dict(json.load(open("стенд_вх.json", encoding="utf-8")),
            намір="conventional", без_фото=1)


def прогін(каталог, сід, K=None):
    вх = dict(база, каталог=каталог, сід=сід)
    if K:
        вх["K"] = K
    з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    if з.get("помилка") or з.get("пул_чому"):
        return "ЗАПИТИ НЕ ЗІБРАЛИСЬ: %s" % (з.get("помилка") or з["пул_чому"])
    речі, поле, порожніх = {}, {}, 0
    for рука, ключ in (("1", "кандидати"), ("2", "кандидати_донора")):
        пул = з.get(ключ) or {}
        порожніх += sum(1 for с in СЛОТИ if с in пул and not пул[с])
        ід = [пул[с][ЯКИЙ % len(пул[с])]["id"] for с in СЛОТИ if пул.get(с)]
        вм = json.loads(B.виклик("від_моделі", json.dumps(
            dict(вх, донор=(рука == "2"), ід=ід), ensure_ascii=False)))
        речі[рука] = [r.get("id") for r in (вм.get("речі") or [])]
        поле[рука] = (вм.get("k_var_01_прогону") or {}).get("суть")
    спільні = [i for i in речі["1"] if i in речі["2"]]
    return ("речей 1/2: %d/%d · ПОВТОРІВ %d%s · порожніх слотів %d · знахідка: %s"
            % (len(речі["1"]), len(речі["2"]), len(спільні),
               (" (" + ", ".join(спільні[:2]) + ")") if спільні else "",
               порожніх, (поле["2"] or "нема")[:60]))


for каталог in ("каталог_brief.xml", "каталог_повний.xml"):
    for сід in (4242, 5, 9):
        print("%-20s сід %-5s %s" % (каталог, сід, прогін(каталог, сід)))
print("%-20s сід %-5s %s" % ("brief · пул=1 річ", 4242, прогін("каталог_brief.xml", 4242, K=1)))
