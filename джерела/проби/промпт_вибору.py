# -*- coding: utf-8 -*-
"""Промпт вибору рук 1–2 до/після П-2 на сирих прогонах ноутбука (ВЕРДИКТ_V1 → ВИБІР_V1).

Той самий вердикт на дроті (старий промпт без `завдання`; вердикт до Т-7 — крізь
`міст_відповіді._вердикт_для_моделі`) крізь `дріт_моделі.вердикт(ремонти=False)` і оголошення
`ВИБІР`: символи й токени gemma (GEMMA_TOKENIZER) старого й нового і загублені факти. Чого вибір
не читає, друкується з причиною: «вітрина» й «мова» — не читав і на main до П-2 (оголошення
ВИБІР, 25.09), «ремонт» знахідки — П-2: вибір не ремонтує, лише обирає й прибирає зайве.
Запуск: cd джерела && GEMMA_TOKENIZER=… python3 проби/промпт_вибору.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import дріт_факти as Ф, дріт_моделі as Д, збирач_промптів as ЗП, повнота_образу as ПО, міст_відповіді as МВ, протокол as П
НЕ_ЧИТАЄ = ("вітрина", "мова", "ремонт")
разом = [0, 0]
for ім, п in Ф.сирі("*ВЕРДИКТ_V1_ВИБІР_V1*"):
    ст = json.loads(п)
    дріт = {к: v for к, v in ст.items() if к != "завдання"}
    дріт = (МВ._вердикт_для_моделі(дріт) if "образи" in дріт
            else dict(дріт, вердикт=[dict(с, чекліст=П._чекліст_на_дріт(с.get("чекліст"))) for с in дріт["вердикт"]]))
    н = json.dumps(ЗП.зібрати(ПО.ВИБІР, Д.вердикт(Ф.з_осями(дріт), ремонти=False), мова_тексту="English"),
                   ensure_ascii=False, separators=(",", ":"))
    без = Ф.загублено(ст, н, ще=НЕ_ЧИТАЄ)
    разом[0] += 1; разом[1] += len(без)
    print("%-44s було %6d симв / %5s ток → стало %6d симв / %5s ток · загублено: %s"
          % (ім[:44], len(п), Ф.ток(п), len(н), Ф.ток(н), без[:6] or "нічого"))
print("прогонів %d, загублених фактів разом %d · не читає: %s" % (разом[0], разом[1], ", ".join(НЕ_ЧИТАЄ)))
