"""Спільне для проб кольору — не проба (як `поділ_спільне`): міри ДО, яких продукт більше не кличе.

`поруч_за_тоном` — відлуння кутом CIELAB (ДО КОЛІР-Р2, рядок 2693); з `колір_річ` знято хвилею 2 КОЛІР-Р4
(рядок 2950): продукт судить тон класами `колір_річ.відношення` на колі художника, а проби ДО/ПІСЛЯ Р1–Р4 мірять
нею бік ДО."""
import колір_річ as КР


def поруч_за_тоном(a, b, поріг):
    """«так» / «ні» / «невідомо»: чи тони двох речей у межах `поріг` градусів CIELAB (`колір_річ.розкид_тону`):
    «так» — усе вікно в межах, «ні» — жодна точка не дістає, інакше «невідомо»."""
    р = КР.розкид_тону(a, b)
    if р is None:
        return "невідомо"
    return "ні" if р[0] > поріг else "так" if р[1] <= поріг else "невідомо"
