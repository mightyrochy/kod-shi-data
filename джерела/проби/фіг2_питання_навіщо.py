# -*- coding: utf-8 -*-
"""ФІГ-2, рядок 1061: чи доїжджає `навіщо` знахідки-питання до блоку `питання` відповіді моста.
Живий міст `від_моделі`, 6 сцен `стенд_знімок`, до 8 верхніх шарів пулу сцени + перший низ + перше взуття.
Друкує: питань усього · з `навіщо` у знахідках суду (`etapy` не читаємо) · з `навіщо` у `питання` моста;
окремо K-FIT-03 і K-SIL-02. Запуск із теки `джерела`: python3 проби/фіг2_питання_навіщо.py"""
import sys, os, json, collections
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge as B, feed as Ф, fit as ПС, стенд_знімок as СЗ
КАТ, База = Ф.каталог_на_диску("каталог_повний.xml"), json.load(open("стенд_вх.json", encoding="utf-8"))
Z, СИРІ = collections.Counter(), []
_к, _о = ПС.краї, ПС.поділ_образу
ПС.краї = lambda *a, **k: (lambda з: (СИРІ.extend(з), з)[1])(_к(*a, **k))
ПС.поділ_образу = lambda *a, **k: (lambda з: (СИРІ.extend(з), з)[1])(_о(*a, **k))
for назва, сцен in СЗ.СЦЕНАРІЇ.items():
    вх = dict(База, каталог=КАТ, сценарій=сцен, випадок=назва)
    пул = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["кандидати"]
    for о in (пул.get("верхній_шар") or [])[:8]:
        СИРІ.clear()
        відп = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=[о["id"], пул["низ"][0]["id"], пул["взуття"][0]["id"]]), ensure_ascii=False)))
        сирі_навіщо = {(з["правило"], str(з.get("суть"))[:120]) for з in СИРІ if з.get("сила") == "питання" and з.get("навіщо")}
        for п in відп.get("питання") or []:
            пр = п.get("правило") if п.get("правило") in ("K-FIT-03", "K-SIL-02") else "інші"
            Z[(пр, "питань")] += 1
            Z[(пр, "навіщо в суді")] += (п.get("правило"), str(п.get("суть"))[:120]) in сирі_навіщо
            Z[(пр, "навіщо в питання моста")] += bool(п.get("навіщо"))
            Z[(пр, "контракт.поле в питання моста")] += bool((п.get("контракт") or {}).get("поле"))
for пр in ("K-FIT-03", "K-SIL-02", "інші"):
    print("%-9s" % пр, " · ".join("%s %d" % (k[1], v) for k, v in Z.items() if k[0] == пр))
