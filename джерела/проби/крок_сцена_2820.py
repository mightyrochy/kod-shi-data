"""Рядок 2820: `перевірити_образ` дає кроку редагування сцену — K-KOH-05 (код, «мусить бути сукня», смуга) входить у
«стало гірше». Код cocktail, +12 °C. ДО — той самий виклик, з якого `сцен` відрізано; ПІСЛЯ — як іде. Моделі не кличе."""
import os, sys                                                                 # noqa: E401
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import проба_правила as ПП, pipeline as PL, суд_образу as СУД                 # noqa: E402
F, T = ПП._особа(), ПП._тіло()
сукня = [ПП.річ("сукня", "#7a1f2b", тип="коктейльна_сукня"), ПП.річ("верхній_шар", "#3a3a3a", тип="пальто"),
         ПП.річ("взуття", "#222222", тип="човники"), ПП.річ("сумка", "#222222", тип="клатч")]
верх_низ = [ПП.річ("верх", "#7a1f2b", тип="блуза"), ПП.річ("низ", "#2a2a2a", тип="спідниця"),
            ПП.річ("верхній_шар", "#3a3a3a", тип="пальто"), ПП.річ("взуття", "#222222", тип="човники"),
            ПП.річ("сумка", "#222222", тип="клатч")]
справжній, бачено = СУД.крок_редагування, []
def без_сцени(*a, **k):
    бачено.append(k.pop("сцен", None) is not None)
    return справжній(*a, **k)
for назва, речі in (("сукня+пальто", сукня), ("блуза+спідниця+пальто", верх_низ)):
    for етап, крок in (("ДО", без_сцени), ("ПІСЛЯ", справжній)):
        СУД.крок_редагування = крок
        вих = PL.перевірити_образ(F, ПП._з_площами([dict(r) for r in речі], T), тіло=T, дрес_код="cocktail", темп_c=12.0)
        к = вих["композиція"]
        print("%-22s %-5s зайві: %-6s база кроку: знахідок %s, вага %s" % (
            назва, етап, ", ".join(sorted({str(z["речі"][0]) for z in к["крок_редагування"]})) or "—",
            к["метрики"].get("знахідок"), к["метрики"].get("вага_знахідок")))
СУД.крок_редагування = справжній
print("pipeline передає сцену в %d із %d викликів кроку (у ДО її відрізано в цій пробі)" % (sum(бачено), len(бачено)))
