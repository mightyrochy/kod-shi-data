"""КОЛІР-КОДУВАННЯ (рядок 2690), п.1: звідки колір речі на `каталог_повний` (рука 1) і що з нього може сказати
правило, яке порівнює дві речі. Вид: «точка» (вимір пікселів, поля `колір_не_вимір` нема) / «вікно» (свідок —
слово крамниці, слово моделі, hex жнив v1) / «невідомо» (кольору нема) — за родом слота й гучністю (C* запису:
≥40 гучна, 15–40 середня, <15 тиха). Для вікон: ширина дуги тону й чи лежить поруч вимір жнив v2
(`каталог_збагачення.json.gz`, hex маски) — тобто вимір є, але код його не взяв, і чому (поле `чому`).
Запуск із джерела/: python3 проби/колір_джерела_покриття.py"""
import json, gzip, sys, collections as K
sys.path.insert(0, "."); import bridge as B, стенд_знімок as СЗ, colorspace as cs, колір_річ as КР
from аксесуари_структура import СЛОТИ_АКСЕСУАРІВ
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
B.виклик("запити", json.dumps(dict(вх, сценарій=СЗ.СЦЕНАРІЇ["офіс·18°C"], випадок="офіс"), ensure_ascii=False))
кат, зб = B.каталог_останнього_пакета(), json.load(gzip.open("каталог_збагачення.json.gz"))
ОДЯГ = {"верх", "низ", "сукня", "комплект", "верхній_шар"}
рід = lambda с: "одяг" if с in ОДЯГ else "взуття" if с == "взуття" else "аксесуар" if с in СЛОТИ_АКСЕСУАРІВ or с in ("пояс", "головний_убір", "браслет", "каблучка", "брошка", "кольє", "прикраси") else "інше"
def вид(r):
    нв = КР.не_вимір(r)
    return "невідомо" if not r.get("lab") else "точка" if нв is None else "вікно: " + нв["свідок"]
def гучн(r):
    C = cs.lch(tuple(r["lab"]))[1] if r.get("lab") else -1
    return "гучна" if C >= 40 else "середня" if C >= 15 else "тиха" if C >= 0 else "?"
def чому(r):
    ч = (КР.не_вимір(r) or {}).get("чому", "")
    for к in ("згода свідків", "в спорі", "спільна картинка", "придатного для виміру", "жнива v1", "з опису фото"):
        if к in ч: return к
    return "інше"
Т, Ч, Ш, Г = K.Counter(), K.Counter(), K.defaultdict(list), K.Counter()
for r in кат:
    в, р, г = вид(r), рід(r.get("слот")), гучн(r); Т[(р, г, в)] += 1; Г[(г, в.split(":")[0])] += 1
    if в.startswith("вікно"):
        д = КР.межі_кольору(r)[4]; Ш[г].append(0 if д is None else (д[1] - д[0]) % 360)
        v2 = (зб.get(r["id"]) or {}).get("версія") == 2 and (зб[r["id"]].get("колір_основний") or {}).get("hex")
        Ч[("вимір v2 поруч" if v2 else "виміру нема", чому(r))] += 1
print("речей:", len(кат))
for (р, г, в), n in sorted(Т.items()): print("  %-9s %-8s %-26s %5d" % (р, г, в, n))
print("за гучністю (усі слоти):", {"%s/%s" % к: n for к, n in sorted(Г.items())})
for г, w in sorted(Ш.items()): w.sort(); print("  дуга тону вікна, %s: медіана %d°, ≥45° у %d з %d" % (г, w[len(w) // 2], sum(x >= 45 for x in w), len(w)))
print("вікна — чи є вимір жнив v2 і чому код його не взяв:")
for к, n in Ч.most_common(): print("  %-18s %-24s %5d" % (к[0], к[1], n))
