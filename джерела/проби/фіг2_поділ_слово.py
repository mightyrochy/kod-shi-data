# -*- coding: utf-8 -*-
"""ФІГ-2, рядок 1060: K-SIL-02 над краєм верхнього шару, узятим зі СЛОВА (зона ±розкид, не точка).
Тіло стенда (`стенд_вх.json`), кожен верхній шар пакета каталогу окремо, без пари (підйом 0).
Друкує по джерелу краю: речей · K-SIL-02 вердикт · K-SIL-02 питання; і для краю «слово» —
скільки мають центр і всю зону у вікні (і для «виріб» — зона розмірної сітки). Запуск із теки `джерела`: python3 проби/фіг2_поділ_слово.py"""
import sys, os, json, math, collections
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge as B, feed as Ф, fit as ПС, композитор_річ as КР, стенд_знімок as СЗ
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), каталог=Ф.каталог_на_диску("каталог_повний.xml"))
вх.update(сценарій=next(iter(СЗ.СЦЕНАРІЇ.values())), випадок=next(iter(СЗ.СЦЕНАРІЇ)))
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
T = ПС.тіло(float(вх["зріст"]), {k: float(v) for k, v in вх["обхвати"].items()})
пл, Z = T["висоти"]["плечі"], collections.Counter()
у_вікні = lambda л: abs(math.log((пл - л) / л)) < ПС.C["поділ_рівний"] if 0 < л < пл else False
for c in B.каталог_останнього_пакета():
    if c.get("слот") != "верхній_шар": continue
    р = КР._у_річ(dict(c), "верхній_шар", T)
    дж = р.get("край_джерело") or "?"
    зн = [з for з in ПС.поділ_образу(T, [р]) if з["правило"] == "K-SIL-02"]
    Z[(дж, "речей")] += 1
    Z[(дж, "вердикт")] += any(з["сила"] not in ("питання", "утримано") for з in зн)
    Z[(дж, "питання")] += any(з["сила"] == "питання" for з in зн)
    if дж in ("слово", "виріб") and р.get("край_розкид_см"):
        л, рз = min(р["верх_см"], р["низ_см"]), float(р["край_розкид_см"])
        Z[(дж, "центр у вікні")] += у_вікні(л)
        Z[(дж, "уся зона у вікні")] += у_вікні(л - рз) and у_вікні(л + рз)
print("плечі %.1f см, вікно K-SIL-02 %.1f–%.1f см" % (пл, пл / (1 + math.exp(ПС.C["поділ_рівний"])),
      пл / (1 + math.exp(-ПС.C["поділ_рівний"]))))
for дж in sorted({k[0] for k in Z}):
    print("%-14s" % дж, " · ".join("%s %d" % (k[1], v) for k, v in Z.items() if k[0] == дж))
