import collections, os, re, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import фід_каталог as ФК, траурний_регістр as ТР                               # noqa: E401,E402
к = ФК._прочитати_каталог(ФК.каталог_на_диску(), ліміт_фото=0)["каталог"]
взуття = [r for r in к if r.get("слот") == "взуття"]
r = next(x for x in взуття if x["id"] == "ж-09117@cultboutique.com.ua")
тр = ТР.траур_випадку("траур", "похорон")
print("ж-09117: тип=%s текстура=%s блиск=%s матеріал_фото=%s виріз_стопи=%s" % (
    r.get("тип"), r.get("текстура"), r.get("блиск"), r.get("матеріал_фото"), r.get("виріз_стопи")))
print("  біля обличчя: %s · траурне відсічення: %s" % (ТР.біля_обличчя(r), ТР.траурне_відсічення(r, тр)))
бл = [x for x in взуття if (x.get("блиск") or 0) >= ТР.БЛИСК_ГЛЯНЕЦЬ]
print("взуття %d, блиск ≥%d: %d (лак за текстурою/фото: %d)" % (len(взуття), ТР.БЛИСК_ГЛЯНЕЦЬ, len(бл), sum(
    1 for x in бл if x.get("текстура") == "patent" or x.get("матеріал_фото") == "лак")))
поля = sorted({k for x in взуття for k in x if re.search(r"п.ят|носок|носк|відкрит|open|toe|heel", k)})
print("поля фіду взуття про відкриту п'яту/носок:", поля or "нема")
корп = open("аудит/ПРАВИЛА.md", encoding="utf-8").read()
м = re.search(r"\*\*K-OCC-01\..*?no shine near the face\.", корп)
print("корпус K-OCC-01:", м.group(0)[:160] if м else "не знайдено")
