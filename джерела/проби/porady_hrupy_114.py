# -*- coding: utf-8 -*-
"""Рядок 114: поради стилістки ГРУПАМИ. Власник 20.09.2026 про «не більше однієї за хід»: «це
довго і буде затягувати розмову. Краще якось групувати». Проба моделює розмову, де жінка поради
ІГНОРУЄ (хід n+1 бачить теми ходу n у `поради_дані`), для 6 сценаріїв стенда і 3 типових паспортів:
скільки доречних тем, за скільки ходів вичерпались ДО (1 тема/хід — те саме число дає ця ж проба на
`origin/main`) і ПІСЛЯ, і що жодна не повторилась. Запуск: cd джерела && python3 проби/porady_hrupy_114.py"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import pipeline as PL
from стенд_знімок import СЦЕНАРІЇ

ВИПАДКИ = list(СЦЕНАРІЇ.items()) + [
    ("вечір·ресторан·20:00", dict(нагода="побачення", місце="ресторан_районний", година=20, темп_c=14)),
    ("парк·діти·без °C", dict(нагода="щоденне", місце="парк", формат="просто неба", година=11)),
    ("офіс·удень", dict(нагода="робота", місце="офіс", година=13, темп_c=20, дрес_код="business_casual")),
]


def теми_ходу(п):
    """Теми ходу обома формами `порада_коду` — групою (`теми`, ця гілка) і однією темою
    (`тема`, origin/main): та сама проба міряє ДО і ПІСЛЯ без правок."""
    return ([] if not п else list(п["теми"]) if "теми" in п else [п["тема"]])

разом_до, разом_після, повторів, макс_за_хід = 0, 0, 0, 0
for назва, сц in ВИПАДКИ:
    дані, ходи = [], []
    while len(ходи) < 12:
        т = теми_ходу(PL.порада_коду(сц, dict(поради_дані=list(дані)), ""))
        if not т:
            break
        повторів += sum(1 for x in т if x in дані)
        макс_за_хід = max(макс_за_хід, len(т))
        ходи.append(т); дані += т
    разом_до += len(дані); разом_після += len(ходи)
    print("%-22s тем %d · ходів ДО %d · ходів ПІСЛЯ %d · за хід %s"
          % (назва, len(дані), len(дані), len(ходи), " | ".join(",".join(х) for х in ходи) or "—"))
print("\nразом: доречних тем %d · ходів ДО (1 тема/хід) %d · ходів ПІСЛЯ %d (менше у %.1f раза) · тем за хід"
      " ≤ %d · повторів тем %d" % (разом_до, разом_до, разом_після, разом_до / max(разом_після, 1),
                                   макс_за_хід, повторів))
assert повторів == 0 and макс_за_хід <= PL.ПОРАД_ЗА_ХІД_МАКС and разом_після < разом_до
