"""Виміряти межу підтвердження без словників і тлумачення заперечень кодом."""
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import мовний_шар as м

def main():
    """Переказ лишається моделі; коди ходу, числа, шкали й питання судить код."""
    картка = dict(goal=dict(label='Непомітно', quote='не хочу виділятись', source='her'),
                  temperature_c=dict(label='+18 °C', quote='+18', source='her'))
    випадки = [
        ('Тобі комфортніше залишатися непомітною.', ['goal'], True),
        ('Не хочу виділятись.', ['goal'], True),
        ('На вулиці +18 °C.', ['temperature_c'], True),
        ('На вулиці +21 °C.', ['temperature_c'], False),
        ('Непомітно.', ['place'], False),
        ('Середня ошатність.', ['formality'], False),
        ('Тобі комфортніше залишатися непомітною?', ['goal'], False),
    ]
    відмов = 0
    for текст, коди, очікується in випадки:
        частини = dict(text_parts=[dict(about=коди, says=текст)])
        прийнято, _, причини = м._текст_до_показу(частини, картка, картка=картка)
        гаразд = bool(прийнято) == очікується and (not прийнято or прийнято == текст)
        відмов += not гаразд
        print(json.dumps(dict(текст=текст, about=коди, прийнято=прийнято, причини=причини, гаразд=гаразд), ensure_ascii=False))
    for поле in ('answer', 'added'):
        текст = 'Не хочу підборів; натомість обираю кеди за 1200.'
        відмов += м.суд_репліки(текст, {поле: текст})[0] != текст
    порада = 'Можеш назвати прикраси.'
    хід = м.паспорт_з_шару({}, {}, паспорт_досі=dict(нагода='робота', місце='офіс'),
                          частини=dict(need='none', invite_topics=['jewelry'], invite=порада))
    відмов += хід['текст'] != порада or хід['мовець'] != 'turn'
    print('порушень межі підтвердження:', відмов)
    return int(bool(відмов))


if __name__ == '__main__':
    sys.exit(main())
