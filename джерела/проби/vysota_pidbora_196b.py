# -*- coding: utf-8 -*-
"""Рядок 196 (доробка після приймання): висота з поля крамниці, якого жниварка не
звела в `каблук_см`. Скільки пар її дістало, чи не суперечать їй інші свідки
(класи рядка 178) і що це міняє для вето «без підборів» і стелі каблука.
Запуск із `джерела`: PYTHONPATH=. python3 проби/vysota_pidbora_196b.py"""
import sys, re, collections; sys.path.insert(0, ".")
import feed as Ф, фід_взуття as ФВ, profile as П
offers, _ = Ф.читати_yml(Ф.каталог_на_диску())
ПЛАСК, ПІДБ = ("без підбор", "без каблук", "на пласк", "на плоск"), ("на підбор", "на каблук", "шпильк", "танкет")
нові, крамниці, спори, високі = [], collections.Counter(), collections.Counter(), 0
for o in offers:
    п = o.get("параметри") or {}
    if ФВ._число_см(п.get("каблук_см")) is not None or ФВ._смуга_з_параметрів(п):
        continue
    h = ФВ.висота_з_параметрів(п)
    if not h:
        continue
    поля = ФВ._взуттєві_поля(o, Ф.тип_речі(o))
    нові.append((o["id"], h[0], поля.get("каблук"), str(o.get("назва"))[:38]))
    крамниці[o["id"].split("@")[1]] += 1
    високі += (h[0] >= 4.0)
    текст = " ".join([str(o.get("назва") or ""), str(o.get("опис") or "")]).lower()
    м = ФВ._ПРО_КАБЛУК.search(текст)
    if h[0] >= 3 and any(x in текст for x in ПЛАСК) and "платформ" not in текст: спори["A пласке слово"] += 1
    if h[0] == 0 and any(x in текст for x in ПІДБ): спори["B слово про підбори"] += 1
    if м and abs(float(м.group(1).replace(",", ".")) - h[0]) > 1: спори["C число в тексті"] += 1
print("пар, де висота БУЛА в полі, але код її не знав: %d %s" % (len(нові), dict(крамниці)))
print("з них ≥ 4 см (стеля K-SHO-16 `каблук_смуга_низ`): %d · тепер `каблук` True: %d"
      % (високі, sum(1 for x in нові if x[2] is True)))
print("свідки проти (класи рядка 178): %s" % (dict(спори) or "жоден не суперечить"))
речі = [dict(слот="взуття", id=і, назва=н, каблук_см=h, каблук=(h > 0)) for і, h, k, н in нові]
_, знято = П.жорстке_ні_фільтр(речі, ["без підборів"])
print("вето «без підборів» знімає з них: %d (доти 0 — код не знав ні висоти, ні `каблук`)" % len(знято))
for і, h, k, н in sorted(нові, key=lambda x: -x[1])[:5]:
    print("   %s · %.1f см · %s" % (і, h, н))
