# -*- coding: utf-8 -*-
"""Рядок 1043 (КОЛО-1): друга сторона «приглушеної комплементарної» — ДО: протилежність у CIELAB
((h+180)%360 ±18°), ПІСЛЯ: `colorspace.доповнення` (коло художника, K-COL-03 §4: «burgundy + pine, camel +
navy, teal + copper»). Міряє на ПОВНОМУ каталозі великі речі (верх, низ, сукня, верхній шар, комплект),
що несуть колір (`palettes._хроматична`): скільки в кожній дузі ±18°, медіана L*, частка темних (L*<45).
hex сторін — типові зразки слів (не з каталогу); друга звірка — медіани тону речей каталогу з тим самим
словом кольору (останній блок): опори кола підібрано так, щоб обидві сходились у межах 10°.
Запуск із `джерела`: python3 проби/комплемент_дуги_1043.py"""
import sys, pathlib, math, statistics as С
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import feed as F; F.каталог_на_диску('каталог_повний.xml')
import фід_каталог as ФК, colorspace as cs, palettes as P
кат = ФК._прочитати_каталог('каталог_повний.xml', 0)['каталог']
ВЕЛ = {"верх", "низ", "сукня", "верхній_шар", "комплект"}
лч = [cs.lch(tuple(r["lab"])) for r in кат if r.get("слот") in ВЕЛ and r.get("lab") and P._хроматична(tuple(r["lab"]))]
ПАРИ = (("бордо", "#6e2a2c", "сосна", "#2e4a3a"), ("кемел", "#c19a6b", "темно-синій", "#1f2a44"),
        ("бірюза-тіл", "#2f7f80", "мідь", "#b87333"))
h_ = lambda x: cs.lch(cs.hx(x))[2]
кут = lambda a, b: min(abs(a - b) % 360, 360 - abs(a - b) % 360)
def дуга(h, ш=18):
    у = [L for L, C, hh in лч if кут(hh, h) <= ш]
    return "%4d речей · медіана L* %4.1f · темних (L*<45) %3d (%2.0f%%)" % (
        len(у), С.median(у) if у else 0, sum(L < 45 for L in у), 100 * sum(L < 45 for L in у) / max(1, len(у)))
print("великих кольорових речей у каталозі: %d" % len(лч))
for а, ах, б, бх in ПАРИ:
    ha, hb = h_(ах), h_(бх)
    for хто, hc in (("ДО (h+180)", (ha + 180) % 360), ("ПІСЛЯ коло", cs.доповнення(ha))):
        print("%-10s h=%5.1f° | %-11s %5.1f° (розходження з корпусом %3.0f°) → %s" % (а, ha, хто, hc, кут(hc, hb), дуга(hc)))
    print("%-10s          | корпус: %-11s h=%5.1f°                        → %s" % ("", б, hb, дуга(hb)))
def мед(слова):
    hs = [cs.lch(tuple(r["lab"]))[2] for r in кат if r.get("колір_назва") in слова.split("|") and r.get("lab") and cs.lch(tuple(r["lab"]))[1] > 8]
    return math.degrees(math.atan2(sum(math.sin(math.radians(h)) for h in hs), sum(math.cos(math.radians(h)) for h in hs))) % 360, len(hs)
for а, б in (("бордовий|бордо|бургунді", "темно-зелений|хвойний|смарагдовий"), ("кемел", "темно-синій"),
             ("бірюзовий|петроль", "теракотовий|рудий")):    # мідного слова в каталозі нема — найближчі
    (ha, na), (hb, nb) = мед(а), мед(б)
    print("каталог: %-22s %5.1f° (n=%3d) → ДО %5.1f° (розх. %3.0f°) · ПІСЛЯ %5.1f° (розх. %3.0f°) · %s %5.1f° (n=%d)" % (
        
        а, ha, na, (ha + 180) % 360, кут((ha + 180) % 360, hb), cs.доповнення(ha), кут(cs.доповнення(ha), hb), б, hb, nb))
