# -*- coding: utf-8 -*-
"""Рядок 1043 (СХЕМА-2): друга сторона «приглушеної комплементарної» — протилежність у CIELAB (код:
`палітра_схеми`, (h+180)%360 ±18°) проти пар корпусу K-COL-03 §4 («burgundy + pine, camel + navy, teal +
copper» — коло художника). Міряє на ПОВНОМУ каталозі великі речі (верх, низ, сукня, верхній шар, комплект),
що несуть колір (`palettes._хроматична`): скільки в кожній дузі ±18°, медіана L*, частка темних (L*<45).
hex сторін — типові зразки слів (не з каталогу). Запуск із `джерела`: python3 проби/комплемент_дуги_1043.py"""
import sys, pathlib, statistics as С
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import feed as F; F.каталог_на_диску('каталог_повний.xml')
import фід_каталог as ФК, colorspace as cs, palettes as P
кат = ФК._прочитати_каталог('каталог_повний.xml', 0)['каталог']
ВЕЛ = {"верх", "низ", "сукня", "верхній_шар", "комплект"}
лч = [cs.lch(tuple(r["lab"])) for r in кат if r.get("слот") in ВЕЛ and r.get("lab") and P._хроматична(tuple(r["lab"]))]
ПАРИ = (("бордо", "#6e2a2c", "сосна", "#2e4a3a"), ("кемел", "#c19a6b", "темно-синій", "#1f2a44"),
        ("бірюза-тіл", "#2f7f80", "мідь", "#b87333"))
h_ = lambda x: cs.lch(cs.hx(x))[2]
def дуга(h, ш=18):
    у = [L for L, C, hh in лч if min(abs(hh - h), 360 - abs(hh - h)) <= ш]
    return "%4d речей · медіана L* %4.1f · темних (L*<45) %3d (%2.0f%%)" % (
        len(у), С.median(у) if у else 0, sum(L < 45 for L in у), 100 * sum(L < 45 for L in у) / max(1, len(у)))
print("великих кольорових речей у каталозі: %d" % len(лч))
for а, ах, б, бх in ПАРИ:
    ha, hb = h_(ах), h_(бх); hc = (ha + 180) % 360
    розх = min(abs(hc - hb), 360 - abs(hc - hb))
    print("%-10s h=%5.1f° | код (h+180) %5.1f° → %s" % (а, ha, hc, дуга(hc)))
    print("%-10s          | корпус: %-11s h=%5.1f° (розходження з кодом %3.0f°) → %s" % ("", б, hb, розх, дуга(hb)))
