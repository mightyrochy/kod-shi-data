# -*- coding: utf-8 -*-
"""ПРОБА: скільки карток лишиться зі «своїм кадром», коли кадр БЕЗ виміряного класу на
картку не пускати (ручна перевірка #409, 27.09.2026). Прогін вимірів ішов `--без-аркуша`,
класу не міряв, і 7 із 25 оглянутих карток «свій_кадр» показали річ не того кольору —
чужий товар, банер або інший колірний варіант. Друкує ДО і ПІСЛЯ одним прогоном
(перемикач `ФКК.КЛАС_ПОТРІБЕН`). ЗАПУСК (тека `джерела`): python проби/klas_kadru_409.py"""
import collections, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed as F
import фід_кадр_колір as ФКК
from фід_фото import _спільні_фото, _файл_фото, чужий_кадр
from фід_збагачення import _збагачення_придатне

offers = F.читати_yml(F.каталог_на_диску())[0]
зб = F.читати_збагачення()
сп = _спільні_фото(offers)
к = ФКК.контекст(offers, зб, сп)
цілі = [(o, з) for o in offers for з in (зб.get(o.get("id")),)
        if _збагачення_придатне(з) and not чужий_кадр(з.get("фото"), сп.get(o.get("магазин")) or {})]


def прогін():
    """(лічба станів, скільком «свій_кадр» кадр дістався БЕЗ виміряного класу)."""
    стани, без_класу = collections.Counter(), 0
    for o, з in цілі:
        р = ФКК.рішення(o, з, к)
        стани[р["стан"]] += 1
        if р["стан"] == "свій_кадр" and any(
                в.get("файл") == _файл_фото(р["кадр"]) and not в.get("клас")
                for в in (к["кадри"].get(o.get("id")) or ())):
            без_класу += 1
    return стани, без_класу


print("речей із придатним збагаченням: %d" % len(цілі))
for потрібен in (False, True):
    ФКК.КЛАС_ПОТРІБЕН = потрібен
    стани, бк = прогін()
    print("клас обов'язковий=%-5s → свій_кадр %4d (на кадрі без класу %4d), заяв «інший_колір» %4d"
          % (потрібен, стани["свій_кадр"], бк, стани["інший_колір"]))
