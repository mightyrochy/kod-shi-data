"""ПРОЗА-1 (рядок 970): сирі відповіді шару «тексти для жінки» з теки VIDPOVIDI живого стенда.
ДРУКУЄ на теку: відповідей шару текстів, із них — з кількома JSON-об'єктами (модель дописала
«виправлену» версію), скільки розбирає суворий `протокол.розбір` (ДО) і `мовний_шар._обʼєкт`
з нотатками (ПІСЛЯ), і скільки слів не кирилицею лишилось у прочитаних текстах (ВМ-3в на їхніх
повторах міряє показ; тут — грубо: слово з латинською літерою і кириличною або латинське від 3 літер).
ЗАПУСК (тека `джерела`): python3 проби/проза1_вікл.py <тека вікл>…"""
import glob, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import мовний_шар as МШ, протокол as ПР

РОЛЬ = МШ.ПРОМПТ_ВИХОДУ.split("\n")[0]
МІШАНЕ = re.compile(r"\b(?=\w*[A-Za-z])(?=\w*[А-Яа-яІіЇїЄєҐґ])\w+\b")

for тека in sys.argv[1:]:
    усі = кілька = до = після = 0
    мішані = []
    for ф in sorted(glob.glob(os.path.join(тека, "*мовний_шар.txt"))):
        т = open(ф, encoding="utf-8").read()
        if РОЛЬ not in т or "── ВІДПОВІДЬ" not in т:
            continue
        в = т.split("── ВІДПОВІДЬ", 1)[1].split("──\n", 1)[1]
        усі += 1
        кілька += len(МШ._ПОЧАТОК_ОБʼЄКТА.findall(в)) > 1
        до += ПР.розбір(в)[0] is not None
        об, _ = МШ._обʼєкт(в, [])
        if isinstance(об, dict):
            після += 1
            мішані += [с for х in об.values() if isinstance(х, str) for с in МІШАНЕ.findall(х)]
    print("%s: відповідей шару текстів %d · з кількома JSON %d · розібрано ДО %d · ПІСЛЯ %d · "
          "мішаних слів у прочитаному %d %s" % (тека, усі, кілька, до, після, len(мішані), мішані[:6]))
