"""Реєстр проблем каталогу, напрям Б, клас Б9: мірило очима (п.18: 40 речей, що змінили колір, правильних ≥ 38).
#1048 — 0/40 UNGRADABLE (фото 403 у хмарі), #991 Astra — 1/12/27, #959 — 33/2/5. ФАКТ — генеральна сукупність, з якої
мірило мусить брати 40: записи, де колір речі взято з фото, а не зі слова крамниці (слово було), за причиною й
крамницями; і коли знято кадри виміру (очі бачать сьогоднішнє фото, вимір — вересневе).
Запуск: cd джерела && python3 -W ignore проби/каталог_проблеми_б_мірило.py"""
import collections, os, re, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as FK, фід_збагачення as FZ
К = FK._прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"]
зб = FZ.читати_збагачення()
зм = [r for r in К if r.get("колір_назва_джерело") == "фото" and r.get("колір_назва_крамниці")]
print("ФАКТ · записів %d; змінили колір (фото замість наявного слова крамниці): %d (%.1f %%)" % (len(К), len(зм), 100 * len(зм) / len(К)))
print("ФАКТ · причина: %s" % collections.Counter(re.sub(r"«[^»]*»", "«…»", r.get("колір_назва_за_чим") or "")[:60] for r in зм).most_common(5))
print("ФАКТ · крамниці: %s; слоти %s" % (collections.Counter(r["магазин"] for r in зм).most_common(6), collections.Counter(r["слот"] for r in зм).most_common(4)))
дата = collections.Counter((зб.get(r["id"]) or {}).get("знято") for r in К if r.get("колір_hex_фото"))
print("ФАКТ · кадри виміру знято: %s — сайти крамниць міняють фото, а повторного зняття нема" % дата.most_common(4))
