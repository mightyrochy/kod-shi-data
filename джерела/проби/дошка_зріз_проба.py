# -*- coding: utf-8 -*-
"""Зріз історичної когорти відтворює звіт; ГП не множать загальну лічбу."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'прилади'))
from дошка_зріз import читати_розмітку, підрахувати, звіт
from дошка_поля import групи, перевірити_поля
шлях = Path(__file__).resolve().parents[2] / 'аудит/дошка_розбір_глибинний/розмітка.tsv'
від, до = '2026-10-19', '2026-10-26'
записи, невідомі = читати_розмітку(шлях, від, до)
числа = підрахувати(записи, від, до, когорта=True)
assert (числа['нових'], числа['повтор'], числа['регресія']) == (370, 131, 43)
assert (числа['закриттів'], числа['без доказу'], числа['видимих'], числа['видимих авто']) == (153, 13, 65, 0)
assert [числа[к] for к in ('власник', 'живий', 'проба', 'виконавець', 'перевірка', 'мірило', 'процес')] == [0, 68, 2, 172, 109, 90, 39]
assert '131/370 (35 %)' in звіт(записи, від, до, когорта=True)
assert групи('копія-поняття+неповна-правка') == {'ГП-4'}
assert групи('копія-поняття+нема-мірила') == {'ГП-1', 'ГП-4'}
try:
    читати_розмітку(шлях, '2026-10-20', до)
    raise AssertionError('неповний тиждень приховав відсутність денних дат')
except ValueError:
    pass
for поле, значення in [('дата', '2026-02-30'), ('попередник', 'регресія #1'), ('механізм', 'описка'), ('доказ', 'текст')]:
    assert any(f'поле {поле}:' in п for п in перевірити_поля(f'<!-- дошка: {поле}={значення} -->'))
print('19–26.10: 370 нових; 131/370 повторів (35 %); 43/370 регресій (12 %); закриттів когорти 153, без доказу 13; видимих 65, авто 0; усі колонки §3 збігаються')
