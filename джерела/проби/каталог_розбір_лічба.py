# -*- coding: utf-8 -*-
"""Проба: на ЗБЕРЕЖЕНИХ відповідях прогону розбору каталогу друкує факт — валідний JSON,
покриття кожного поля і незгоду з чинними словниками коду. Моделі не кличе.
Запуск: python3 джерела/проби/каталог_розбір_лічба.py <тека від каталог_розбір_прогін.py>"""
import json, os, sys                                                          # noqa: E401
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import каталог_розбір as КР, фід_каталог as ФК, фід_розбір as ФР               # noqa: E401,E402
тека = sys.argv[1] if len(sys.argv) > 1 else sys.exit("треба тека прогону")
мірка = json.load(open(os.path.join(тека, "прогін.json"), encoding="utf-8"))
офери = {o["id"]: o for o in ФР.читати_yml(ФК.каталог_на_диску(), показ=False)[0]}
валідні, причини, покр, види, незгоди, збої_коду = 0, [], {ш: 0 for ш, _, _ in КР.ПОЛЯ}, {}, [], {}
for р in мірка["речі"]:
    сире = open(os.path.join(тека, р["файл"]), encoding="utf-8").read()
    поля, пр = КР.з_відповіді(сире.split("── ВІДПОВІДЬ", 1)[-1])
    причини += [(р["файл"], т) for т in пр]
    if not поля:
        continue
    валідні += 1
    for ш, є in КР.покриття(поля).items():
        покр[ш] += 1 if є else 0
    код, збої = КР.що_каже_код(офери[р["id"]]); збої_коду.update(збої)  # noqa: E702
    for вид, ш, к, м in КР.незгода(код, поля):
        види[(вид, ш)] = види.get((вид, ш), 0) + 1
        if вид == "незгода":
            незгоди.append((р["id"], ш, к, м))
n = len(мірка["речі"]) or 1
print("модель %s · мова %s · речей %d · валідний JSON %d (%d %%) · впало викликів %d"
      % (мірка["модель"], мірка["мова"], n, валідні, round(100 * валідні / n),
         sum(1 for р in мірка["речі"] if р["впало"])), flush=True)
print("покриття полів (з %d валідних):" % валідні)
for ш, _, _ in КР.ПОЛЯ:
    print("  %-18s %2d  %3d %%" % (ш, покр[ш], round(100 * покр[ш] / (валідні or 1))))
for вид in ("незгода", "код не знає", "модель не знає"):
    п = sorted(((ч, ш) for (в, ш), ч in види.items() if в == вид), reverse=True)
    print("%s: %d на %d полях · %s" % (вид, sum(ч for ч, _ in п), len(п),
                                       ", ".join("%s×%d" % (ш, ч) for ч, ш in п[:12])))
for id_, ш, к, м in незгоди:
    print("  НЕЗГОДА %-26s %-14s код=%-14s модель=%s" % (id_, ш, к, м))
print("вад форми відповіді: %d · %s" % (len(причини), "; ".join(т for _, т in причини[:6])))
print("збої коду на звірці: %s" % (збої_коду or "нема"))
