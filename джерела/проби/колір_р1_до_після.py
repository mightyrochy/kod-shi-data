"""КОЛІР-Р1 (рядки 2691, 2692, 2695; ГГ-1 — 2660, 2662, 2850): ті самі 4 сцени стенда й сід 7, що `колір_опори_до_після.py` (#715), — 40 випадкових
образів живим судом (`pipeline.перевірити_від_моделі`): скільки образів несуть знахідку правил, що читають гучність і
сім'ю кольору (K-ACC-01 витрата / опора, K-COL-02, K-COMP-03), і скільки — запис «без входу» тих самих правил; плюс пари
«гучний одяг × гучний аксесуар» кандидатів: гучність кожної речі (C* ≥ 40 за виміром чи «так / можливо» за межами вікна)
і відлуння (`поруч_за_тоном`, дуга `ДУГА_ВІДЛУННЯ`) — «так» / «ні» / «невідомо». ДО — та сама проба на базовій гілці.
Запуск із джерела/: python3 проби/колір_р1_до_після.py"""
import json, random, sys, collections as K
sys.path.insert(0, "."); from суд_ремесло import ДУГА_ВІДЛУННЯ; import bridge as B, fit as ПС, colorspace as cs, pipeline as PL, стенд_знімок as СЗ
import колір_річ as КР, колір_спільне as КС, аксесуари_структура as АС
вх0 = json.load(open("стенд_вх.json", encoding="utf-8"))
T = ПС.тіло(float(вх0["зріст"]), {k: float(v) for k, v in вх0["обхвати"].items()}); F = cs.features(cs.hx(вх0["шкіра"]), cs.hx(вх0["волосся"][0]), cs.hx(вх0["очі"]))
def гучн(x):   # ДО (база без `_гучна_речі`) — центр вікна: C* ≥ 40
    return АС._гучна_речі(x) if hasattr(АС, "_гучна_речі") else ("так" if (АС._C_речі(x) or 0.0) >= 40 else "ні")
СЛОТИ = ("верх", "низ", "сукня", "верхній_шар", "взуття", "сумка", "шарф", "сережки", "намисто"); Л = K.Counter()
ПРАВИЛА = ("K-ACC-01", "K-COL-02", "K-COMP-03")
for назва in ("офіс·18°C", "дощ·ресторан·вечір", "весілля·гість", "спека·парк"):
    сц = dict(СЗ.СЦЕНАРІЇ[назва])
    к = json.loads(B.виклик("запити", json.dumps(dict(вх0, сценарій=сц, випадок=назва), ensure_ascii=False)))["кандидати"]
    кат = B.каталог_останнього_пакета(); зі, rnd = {r["id"]: r for r in кат}, random.Random(7)
    for n in range(10):
        ід = [rnd.choice(к[с])["id"] for с in СЛОТИ if к.get(с) and с not in (("верх", "низ") if n % 2 == 0 else ("сукня",))]
        в = PL.перевірити_від_моделі(ід, F, кат, T, сценарій=dict(сц), кандидати=к)
        for п in ПРАВИЛА:
            Л["(а) %s знахідкою (не питання)" % п] += any(z.get("правило") == п and z.get("сила") != "питання" for z in в.get("знахідки") or [])
            Л["(а) %s «без входу»" % п] += any(z.get("правило") == п and z.get("сила") == "питання" for z in (в.get("знахідки") or []) + (в.get("черга_на_вхід") or []))
        Л["(а) K-ACC-01 опорою"] += any(o.get("правило") == "K-ACC-01" for o in в.get("опори") or [])
        Л["(а) образів з опорою (будь-яке правило; ГГ-1, рядок 2662)"] += bool(в.get("опори"))
        for пр in sorted({o.get("правило") for o in в.get("опори") or []}): Л["(а) опорою %s" % пр] += 1
    г = [(с, зі[r["id"]]) for с, рр in к.items() for r in рр if r["id"] in зі and гучн(зі[r["id"]]) in ("так", "можливо")]
    for с1, x in г:
        for с2, y in г:
            if с1 in АС.СЛОТИ_АКСЕСУАРІВ or с2 not in АС.СЛОТИ_АКСЕСУАРІВ: continue
            гг = "обидві гучні" if гучн(x) == гучн(y) == "так" else "хоч одна «можливо»"
            Л["(б) пар %s: відлуння %s" % (гг, КС.поруч_за_тоном(y, x, ДУГА_ВІДЛУННЯ))] += 1
for к_, v in sorted(Л.items()): print("  %-50s %5d" % (к_, v))
