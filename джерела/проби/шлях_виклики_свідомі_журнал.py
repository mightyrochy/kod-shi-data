# -*- coding: utf-8 -*-
"""Розбір шляху 4/8 · колонка «свідомі» у файлі вердиктів. Показ збирає її з КОЖНОГО виклику руки і з КОЖНОГО
образу набору (`показ.html`, `відМоделіРуки` → `свідоміХоду`), а склад картки — один образ. Друкує для рук 1–2
файлів власника 25.09: скільки оголошень у колонці, скільки з них про речі, яких на картці нема, і — де файл
несе запит опису — скільки оголошень справді пішло в промпт ОПИС_V1.
Запуск: cd джерела && python3 проби/шлях_виклики_свідомі_журнал.py"""
import glob, json, os
for ф in sorted(glob.glob(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../аудит/тести/власник_2026-09-25/verdykty-*.json"))):
    for і, п in enumerate(json.load(open(ф, encoding="utf-8"))["прогони"]):
        for в in п["вердикти"]:
            if в.get("рука") not in ("1", "2"): continue
            назви = [str(r[1] if isinstance(r, list) else (r or {}).get("назва") or "") for r in в.get("речі_образу") or []]
            с = [x for x in str(в.get("свідомі") or "").split("; ") if x]
            поза = [x.split(" — ")[0] for x in с if not any(x.split(" — ")[0][:30] in н or н[:30] in x for н in назви if н)]
            опис = next((x for x in (в.get("етапи") or {}).get("виклики") or [] if x.get("крок") == "опис" and x.get("запит")), None)
            в_опис = len(json.loads(опис["запит"]["текст"]).get("свідомі") or []) if опис else None
            print("%s · прогін %d · рука %s: речей на картці %d · у колонці «свідомі» %d · про речі поза карткою %d%s"
                  % (os.path.basename(ф)[-9:-5], і, в["рука"], len(назви), len(с), len(поза),
                     (" · у промпт опису пішло %d" % в_опис) if в_опис is not None else " · запиту опису у файлі нема"))
            if поза: print("   поза карткою: %s" % "; ".join(поза[:4]))
