# -*- coding: utf-8 -*-
"""R-FEED-07 — «Fit and measurement data are not ingestable from any UA feed».

Межа, яку треба СКАЗАТИ. Доти пакет про неї мовчав, і модель була вільна
написати «сидітиме по фігурі» як факт над полями, яких не існує (fail case
корпусу — «building a fit-match layer on a field that does not exist»).
Проба друкує три числа: скільки записів каталогу несуть бодай одне поле обміру
виробу; що про це каже пакет до й після; і — чесно — скільки обмірів лежить у
СИРОМУ XML, куди вони приходять зішкребеною сторінкою (шлях R-ONT-09, не фід)."""
import sys, pathlib, re, gzip, collections
from xml.etree import ElementTree as ET
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, пакет_моделі as ПМ, суд_образу as С

_ОБМІР = re.compile(r"обхват|напівобхват|півобхват|обміри|заміри|ширина_плеч|довжина_виробу")
_ЧИСЛО = re.compile(r"^\D{0,3}\d{2,3}([.,]\d)?\s*(см)?$", re.I)

кат = Ф._прочитати_каталог(Ф.каталог_на_диску("каталог_повний.xml"), ліміт_фото=0)["каталог"]
з_обміром = [c for c in кат if any(_ОБМІР.search(k) for k in c)]
print("каталог: записів %d · із бодай одним полем обміру виробу %d"
      % (len(кат), len(з_обміром)))
assert not з_обміром, "поле, якого нема, не має права з'явитись мовчки"

# сирий XML: обміри Є, але приходять зішкребеною сторінкою (R-ONT-09), не фідом
одяг, сире = 0, 0
for o in ET.parse(gzip.open(_КОРІНЬ.parent / "каталог_повний.xml.gz")).getroot().iter("offer"):
    п = {(x.get("name") or "").strip().lower(): (x.text or "").strip() for x in o.findall("param")}
    if п.get("слот") not in Ф.СЛОТИ_РОЗМІРУ_ОДЯГУ:
        continue
    одяг += 1
    сире += any(_ОБМІР.search(k) and _ЧИСЛО.match(v) and "модел" not in k for k, v in п.items())
print("сирий XML: одягу %d · з обмірами на сторінці %d (%.1f%%) — канал R-ONT-09 "
      "(зішкребти), у код НЕ заведений" % (одяг, сире, 100 * сире / одяг))

рядок = [в for в in ПМ.СКЛАДАННЯ.правила if "обмірів речей" in в]   # оголошення збирача (25.09)
print("до:    рядка про обміри в пакеті нема — модель вільна стверджувати посадку")
print("після: %s" % рядок[0][:96])
assert len(рядок) == 1

# предикат чекліста називає ПОЛЕ, а не стан «False»
E = [dict(річ="x", слот="сукня", площа=1.0, lab=(50, 0, 0))]
print("вхід «обміри виробу в см»: %s → K-SIZ-02 виходить питанням (%d знахідка)"
      % (С._вхід_є("обміри виробу в см", E, []),
         len(С.розмір_не_посадка([dict(id="x", слот="сукня", розміри=("42", "46"))], E))))
assert С._вхід_є("обміри виробу в см", E, []) is False
E[0]["обміри_см"] = {"груди": 92}          # щойно поле з'явиться — питання замовкне (BREAKS)
assert С._вхід_є("обміри виробу в см", E, []) is True
assert not С.розмір_не_посадка([dict(id="x", слот="сукня", розміри=("42", "46"))], E)
print("з обмірами: вхід є → питання про розмір замовкає само (BREAKS корпусу)")
