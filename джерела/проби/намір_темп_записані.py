"""НАМІР-ТЕМПЕРАТУРА (рядки 2380, 2381, 2383, 2385): записані відповіді мовного шару живого пачки 3+4 (MamayLM,
гілка `claude/zhyvyi-pachka-3i4`, `аудит/живий_пачка34/{ДО,ПІСЛЯ}/{Н1,К7,Н4,Н3}/VIDPOVIDI/*хід_розмови*`;
копія — `живий34_шар.json`) — тим самим швом, що стенд: `прийняти_розмову` → `мова(паспорт_з)`, паспорт досі —
ланцюгом ходів. Без моделі. Друкує після кожного ходу (паспорт досі — ланцюгом, як стенд): намір, мету, дозу (як `міст_пакет` + `композитор_збирання`:
statement — сміливий намір; conventional без цитати й мета не «приховати» — межа 20–40; інакше — нема), `темп_c`,
маршрут ходу (need, коли текст є; без тексту — main), подію й незнайомі коди. Запуск: cd джерела && python3 проби/намір_темп_записані.py"""
import json, os, sys; ТУТ = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.dirname(ТУТ))
import мовний_шар as М
СЦЕНИ = json.load(open(os.path.join(ТУТ, "живий34_шар.json"), encoding="utf-8"))
for сцена, ходи in СЦЕНИ.items():
    досі = {}
    for х in ходи:
        р = М.прийняти_розмову(х["відповідь"])
        слова = х["її_репліки"] + ([х["нове"]] if х["нове"] != "unknown" else [])
        п = досі = json.loads(М.мова({"паспорт_з": р["внутрішня"], "сценарій": {}, "паспорт": досі,
                                      "слова_розмови": слова, "частини": р["частини"]}))["паспорт"]
        нам, мета = п.get("намір") or "conventional", п.get("мета") or "невідомо"
        доза = ("сміливий" if нам == "statement" else "межа" if нам == "conventional" and мета != "приховати"
                and not str(п.get("намір_слова") or "").strip() else "нема")
        print("%-9s %s намір %-15s мета %-9s доза %-8s темп_c %-5s %-5s маршрут %-5s подія %-22s %s"
              % (сцена, х["файл"][-2:], нам, мета, доза, п.get("темп_c"), п.get("погода_відчуття"),
                 "main" if р["причина"] else р["частини"].get("need", "-"), json.dumps(п.get("подія"), ensure_ascii=False),
                 " ".join(р.get("перенесено") or []) or "-"))
