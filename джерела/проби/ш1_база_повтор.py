"""Ш-1, важіль 2: повторний збір не будує базу каталогу наново.

Хід одного збору, скорочений до того, що важить: `запити` (база фіду → слот кеша) →
речі руки 3 з прози (`розбір_відповідей.речі_з_тексту`, тимчасовий каталог) → `запити`
вдруге, як на «Зібрати ще раз». Друкує, чи база справжнього фіду пережила руку 3, час
другого `запити` і чи його відповідь та сама, що в збору, де базу будовано наново
(ДО — так ходив main: слот займав тимчасовий файл). Запуск із теки `джерела`."""
import json, sys, time
sys.path.insert(0, ".")
import bridge as B, feed as F, фід_каталог as ФК, розбір_відповідей as Р, міст_пакет as МП

вх = json.load(open("стенд_вх.json", encoding="utf-8"))
вх["каталог"] = F.каталог_на_диску("каталог_повний.xml")
д = json.dumps(dict(вх, пакети=1), ensure_ascii=False)
ід = [o["id"] for o in F.читати_yml(вх["каталог"])[0][:10]]
д2 = json.dumps(dict(вх, пакети=1, вже_були=ід), ensure_ascii=False)   # «Зібрати ще раз»
ПРОЗА = ("Кремова шовкова блуза, прямий крій, довжина до стегна, кремовий #f2e6d0, шовк\n"
         "Сірі вовняні штани, прямі, довжина до щиколотки, сірий #8a8a8a, вовна\n"
         "Чорні шкіряні лофери, чорний #1a1a1a, шкіра")

т = time.time(); перший = B.виклик("запити", д); с1 = time.time() - т
речі = Р.речі_з_тексту(ПРОЗА)["речі"]
жива = any(к[0] == ФК.os.path.abspath(вх["каталог"]) for к in ФК._КЕШ_БАЗИ)
т = time.time(); другий = B.виклик("запити", д2); с2 = time.time() - т
ФК._КЕШ_БАЗИ.clear(); МП._КЕШ_ПАКЕТА.clear()   # ДО: слот зайняв тимчасовий файл руки 3
т = time.time(); до = B.виклик("запити", д2); с_до = time.time() - т
print("рука 3: речей із прози %d · база фіду в кеші після руки 3: %s" % (len(речі), жива))
print("запити: перший %.1f с · повторний ДО (база наново) %.1f с · ПІСЛЯ %.1f с" % (с1, с_до, с2))
print("відповідь повторного `запити` та сама, що з базою наново: %s" % (другий == до))
