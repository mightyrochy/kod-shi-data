# -*- coding: utf-8 -*-
"""КОЛО-РОЛІ (рядок 4781): сім'я очей — суд проти вікон палітри й пулу. Пул руки 1 (4 сцени стенда), кольорові речі
(`нейтраль_меж` «ні»: нейтраль законна в будь-якому рядку); очі — стенд і ж1–ж9. Суд K-PAL-02/13 — `у_сім_ї_очей`. ДО (дерево до рядка 4781) вікна K-PAL-09/10/14
й добір судили дугу очей твердою дугою CIELAB (`дуга_очей`, запас 10° — вікна, без запасу — добір точки): тут вона
відтворена інлайн. ПІСЛЯ — те, що питає код: `у_вікнах_меж` із записом очей і `фід_добір.підходить`/`описує_річ`
рядка сім'ї очей. Друкує розбіжності «від очей» суд ≠ вікна і суд ≠ пул. Запуск із джерела/: python3 проби/коло_ролі_очі_4781.py"""
import json, glob, sys, collections as K; sys.path.insert(0, ".")
import bridge as B, colorspace as cs, стенд_знімок as СЗ, колір_річ as КР, palettes as ПЛ, фід_добір as Ф
вх0, пул = json.load(open("стенд_вх.json", encoding="utf-8")), {}
for назва in ("офіс·18°C", "дощ·ресторан·вечір", "весілля·гість", "спека·парк"):
    к = json.loads(B.виклик("запити", json.dumps(dict(вх0, сценарій=dict(СЗ.СЦЕНАРІЇ[назва]), випадок=назва), ensure_ascii=False)))["кандидати"]
    пул.update({r["id"]: None for xs in к.values() for r in xs})
кат = {x["id"]: x for x in B.каталог_останнього_пакета()}
речі = [кат[і] for і in пул if і in кат and КР.межі_кольору(кат[і]) and КР.нейтраль_меж(кат[і]) == "ні"]
очі = [вх0["очі"]] + [json.load(open(f, encoding="utf-8"))["eyes"] for f in sorted(glob.glob("../аудит/проби/жінки/ж*.json"))]
def до_дуга(x, д, запас):
    """Тверда дуга CIELAB із запасом, як `у_дугах_меж` до рядка 4781 (вимір — точкою, слово — дугою вікна)."""
    д = ((д[0] - запас) % 360, (д[1] + запас) % 360); м = КР.межі_кольору(x)
    if КР.не_вимір(x) is None: return "так" if КР._на_дузі(м[4][0] % 360, д) else "ні"
    if м[4] is None: return "невідомо"
    вл = {КР._на_дузі(h, д) for h in КР._тони_дуги((м[4][0] % 360, м[4][1] % 360), [д])}
    return "так" if вл == {True} else "ні" if вл == {False} else "невідомо"
Л, розійшлись = K.Counter(), lambda а, б: {а, б} == {"так", "ні"}   # одне каже «від очей», інше — «ні»
так_ні = lambda в: "так" if в else "ні"
for о in очі:
    h = cs.lch(cs.hx(о))[2]; L, C, _ = cs.lch(cs.hx(о)); з = ПЛ.колір_очей(dict(L=L, C=C, h=h)); д = ПЛ.дуга_очей(h)
    q = dict(L_min=0.0, L_max=100.0, C_min=0.0, C_max=1000.0, h_from=д[0], h_to=д[1], очі_запис=з)
    for x in речі:
        суд, вк = КР.у_сім_ї_очей(x, з), КР.вікно_речі(x)
        Л["ДО: суд ≠ вікна"] += розійшлись(суд, до_дуга(x, д, 10.0))
        Л["ДО: суд ≠ пул"] += розійшлись(суд, до_дуга(x, д, 0.0) if вк is None else так_ні(до_дуга(x, д, 10.0) != "ні"))
        Л["ПІСЛЯ: суд ≠ вікна"] += розійшлись(суд, КР.у_вікнах_меж(x, (0, 100), (0, 1000), [], очі=з))
        Л["ПІСЛЯ: суд ≠ пул"] += розійшлись(суд, так_ні(Ф.описує_річ(x["lab"], q, вікно=вк) if вк else Ф.підходить(x["lab"], q)))
        Л["пар річ × очі"] += 1
print("кольорових речей пулу руки 1: %d; очей: %d" % (len(речі), len(очі)))
for к_, v in sorted(Л.items()): print("  %-22s %6d" % (к_, v))
