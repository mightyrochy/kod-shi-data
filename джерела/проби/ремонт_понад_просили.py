"""Ремонт: вердикт каже «образів: 5» (`завдання.образів`), а модель повертає всі 10 — так зробила gemma-4-12b на
«Ір, собаки» (сід 13, рука 2, 25.09). Скільки образів код бере в суд і вибір, і що про решту пише у звіт?
Стенд `стенд_вх.json`, 10 образів складання з пулу руки 1; ремонт — ті самі 10 образів у формі відповіді з «виконано».
Друкує факт. Запуск: cd джерела && python3 проби/ремонт_понад_просили.py"""
import json, os, sys
Д = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, Д); os.chdir(Д)
import bridge as B
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), варіантів=10, ремонт_варіантів=5, без_фото=1)
пул = json.loads(json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["руки"]["1"])["пул"]
н = lambda с, k: пул[с][k % len(пул[с])]["н"]
образи = [dict(ід="о%d" % (і + 1), підпис="образ %d" % (і + 1), речі=[н("верх", і), н("низ", і), н("взуття", і), н("сумка", і)])
          for і in range(10)]
від = lambda т, **д: json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=json.dumps(т, ensure_ascii=False), **д),
                                                                 ensure_ascii=False)))
в1 = від(dict(версія="1", образи=образи))
просили = в1["вердикт"]["завдання"]["образів"]
відповідь = dict(версія="1", образи=[dict(о, виконано=[]) for о in образи])
в2 = від(відповідь, ітерація=2, попередній_вердикт=в1["вердикт"])
пп = (в2.get("розбір_блоків") or {}).get("понад_просили")
print("ФАКТ · ремонт просив %d образів, модель дала %d · у суд пішло %d · вибір — над %d" % (
    просили, len(відповідь["образи"]), len(в2.get("образи") or []), len((в2.get("вибір_над") or {}).get("образи") or [])))
print("ФАКТ · у звіті (розбір_блоків.понад_просили): %s" % (
    "просили %d, дала %d, не взято: %s" % (пп["просили"], пп["дала"], ", ".join(str(х["підпис"]) for х in пп["не_взято"]))
    if пп else "нічого"))
