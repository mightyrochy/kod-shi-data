"""Рядок 1988: «без капюшона», г/м², повнота з поля, міліметри в назві поля — ФАКТ ПІСЛЯ на каталозі.
Запуск: cd джерела && python3 проби/fid2a_1988.py (ДО — на main: капюшон True 23 з 23, опушка 7, грамаж 12, повнота 151)"""
import collections, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_верхнє as ФВ, фід_взуття as ФЗ
оф = feed.читати_yml(feed.каталог_на_диску())[0]
повний = lambda o: " ".join(str(x) for x in (o.get("категорія"), o.get("назва"), o.get("опис"), o.get("параметри"))).lower()
бк = [o for o in оф if "без капюшона" in повний(o)]
ат = {o["id"]: ФВ.верхні_атрибути(o) for o in оф}
print("ФАКТ · «без капюшона» у %d оферах: капюшон %s · опушка=True %d"
      % (len(бк), dict(collections.Counter(ат[o["id"]].get("капюшон") for o in бк)),
         sum(1 for o in бк if ат[o["id"]].get("опушка"))))
print("ФАКТ · власний текст каже «з капюшоном» і «без» у param чужого товару → True лишається: %s"
      % [o["id"][:8] for o in бк if ат[o["id"]].get("капюшон") is True])
грам = [o for o in оф if ат[o["id"]].get("грамаж_г") is not None]
гм2 = [o for o in оф if "г/м" in повний(o) and ФВ._ПРО_ГРАМАЖ.search(повний(o))]
print("ФАКТ · грамаж_г виставлено %d (з «г/м²» — %d); маса «200 г пуху» читається: %s"
      % (len(грам), len(гм2), bool(ФВ._ПРО_ГРАМАЖ.search("наповнювач 200 г пуху"))))
пов = [o for o in оф if ФЗ.повнота_з_параметрів(o.get("параметри"))]
print("ФАКТ · повнота з поля крамниці: %d оферів; «G (середня), F (вузька)» → %s; «Середня» → %s"
      % (len(пов), ФЗ.повнота_з_параметрів({"повнота": "G (середня), F (вузька)"}),
         ФЗ.повнота_з_параметрів({"~повнота:": "Середня"})))
print("ФАКТ · висота підбора з поля в мм: %s · %s · %s"
      % (ФЗ.висота_з_параметрів({"Висота підбора, мм": "35"}), ФЗ.висота_з_параметрів({"висота каблука": "60 мм"}),
         ФЗ.висота_з_параметрів({"висота каблука": "7"})))
