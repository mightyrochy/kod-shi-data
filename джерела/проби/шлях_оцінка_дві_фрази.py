"""Ділянка 8: ДВІ ПРИЧИНИ З УСІХ. `річ_з_фото._рядок_жінці` склеює лише `фрази[:2]` — решту
причин, які код справді знайшов над її річчю, жінка не бачить ніде. Міряє на п'яти речах із
запису 26.09, скільки причин знайдено і скільки сказано.
Запуск із `джерела`: python3 проби/шлях_оцінка_дві_фрази.py"""
import sys, json, inspect, re; sys.path.insert(0, '.')
import річ_з_фото as РФ, colorspace as cs
from міст_вхід import _збірка, _нормалізувати_вхід
джерело = inspect.getsource(РФ._рядок_жінці)
рядок0 = inspect.getsourcelines(РФ._рядок_жінці)[1]
зріз = re.search(r'фрази\[:(\d+)\]', джерело)
print('річ_з_фото.py:%d — `суть = "; ".join(%s)`: стеля причин у рядку жінці = %s'
      % (рядок0 + джерело[:зріз.start()].count('\n'), зріз.group(0), зріз.group(1)))
вх = json.load(open('стенд_вх.json')); F, T, _з, _к = _збірка(_нормалізувати_вхід(dict(вх)))
ОБРАЗ = [('ф1', 'жакет приталений', 'верхній_шар', '#7d7f63', 'хакі', 8),
         ('ф2', 'сорочка з драпуванням', 'верх', '#cfd8e3', 'блакитний', 5),
         ('ф3', 'шкіряна міні-спідниця трапеція', 'низ', '#6b1f2a', 'бордовий', 6),
         ('ф4', 'клатч плетіння', 'сумка', '#7a2230', 'бордовий', 6),
         ('ф5', 'ботильйони на підборах', 'взуття', '#e6dfd2', 'вершковий', 7)]
СЦЕН = dict(нагода='щоденне', місце='зал', година=11, темп_c=18)
лічба = []
_орig = РФ._рядок_жінці
РФ._рядок_жінці = lambda рів, фрази, тип: (лічба.append(len(фрази)), _орig(рів, фрази, тип))[1]
сказано = знайдено = мовчки = 0
for і, н, с, h, к, о in ОБРАЗ:
    р = dict(ід=і, фото=і, назва=н, слот=с, колір=к, ошатність=о, чия='моя',
             вимір=dict(lab=list(cs.hx(h)), hex=h, слово=к))
    в = РФ.вердикт(р, F, T, СЦЕН, типова_нагода=True)
    фраз, у_рядку = лічба[-1], min(лічба[-1], 2)
    причин = фраз + len(в['чекліст']['без_входу'])
    знайдено += причин; сказано += у_рядку; мовчки += фраз - у_рядку
    print('  «%-30s» причин для неї %d + «без входу» %d = %d; у рядку жінці %d'
          % (н[:30], фраз, len(в['чекліст']['без_входу']), причин, у_рядку))
print('разом на образі: причин %d, сказано їй %d, причин утрачено зрізом %d'
      % (знайдено, сказано, мовчки))
print('«без входу» (те, чого коду бракує, щоб судити) в рядок жінці не йде ЖОДНОГО разу —')
print('  воно лишається в `вердикт.чекліст.без_входу`, який у розмові не показує ніхто')
