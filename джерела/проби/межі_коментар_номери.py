"""Коментар образу: коди й місцеві номери на вході, повні id лише після приймання; запуск із джерела/."""
import json, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import мовний_шар as М


def перевірити():
    """Звіряє прив'язку двох схожих речей, чужі номери, порожній образ і повтор без моделі."""
    речі = [dict(id="ж-1@крамниця.ua", назва="Назва крамниці", слот="взуття", тип="чоботи", колір="чорний"),
            dict(id="ж-2@крамниця.ua", назва="Інша назва крамниці", слот="взуття", тип="чоботи", колір="білий")]
    запит = dict(вхід="verdict_comment", слова="Білі чоботи не мої через колір.", речі=речі)
    def виклик(**дод):
        return json.loads(М.мова(dict(запит, **дод)))
    промпт = виклик()["промпт"]
    assert all(р[к] not in промпт for р in речі for к in ("id", "назва"))
    assert all(к in промпт for к in ('"1"', '"2"', 'boots', 'black', 'white', 'shoes'))
    відповідь = json.dumps(dict(about_items=[dict(id="2", opinion="dislike", reasons=["colour"])]))
    р = виклик(відповідь_моделі=відповідь)
    assert р["внутрішня"]["about_items"][0]["id"] == речі[1]["id"]
    assert М.паспорт_з_коментаря(р["внутрішня"])["не_ця"] == [речі[1]["id"]]
    for чужий in ("3", речі[0]["id"], 2, [], {}):
        р = виклик(відповідь_моделі=json.dumps(dict(about_items=[dict(id=чужий, opinion="dislike", reasons=["heels"])])))
        assert not р["внутрішня"].get("about_items") and not р["внутрішня"].get("vetoes")
        assert р["незнайомі"] and р.get("повтор")
    порожній = виклик(речі=[], контекст=dict(items=[dict(id=речі[0]["id"], name=речі[0]["назва"])]))
    assert речі[0]["id"] not in порожній["промпт"] and речі[0]["назва"] not in порожній["промпт"]
    р = виклик(речі=[], відповідь_моделі=відповідь)
    assert not р["внутрішня"].get("about_items") and р["незнайомі"]
    перша = json.dumps(dict(about_items=[dict(id="3", opinion="like")]))
    р = виклик(перша_відповідь=перша, відповідь_моделі=відповідь)
    assert [п["id"] for п in р["внутрішня"]["about_items"]] == [речі[1]["id"]]
    assert "about_items.id=3" in виклик(помилка_формату="about_items.id=3")["промпт"]
    print("Назв/id на дроті: 0/0; коди: 5/5; прив'язка й паспорт: 2/2; чужі посилання: 5/5; порожній: 2/2; повтор: 2/2.")


if __name__ == "__main__":
    перевірити()
