"""Рядок 1883: чи слово сім'ї схеми в рядку жінці накриває зразок, яким сім'ю малює смуга палітри.
Вхід — живий С2 ПІСЛЯ (ж4, весілля, основа «хвойний·тепла·32·середні», приглушена комплементарна, гілка 3;
`simja_slovo_1883.json`), каталог повний. Друкує по сім'ї: зразок смуги (L*, C*, h), слова добору
(`_схема_великі`, з них рядок жінці бере слово), чи вікно вжитку слова накриває зразок, і слово стилістки.
Запуск: cd джерела && python3 проби/simja_slovo_1883.py"""
import json, os, sys, tempfile
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import bridge as B, colorspace as cs, feed as Ф, verify as V
з = json.load(open("проби/simja_slovo_1883.json", encoding="utf-8"))
вх = dict(з["колір"], драп_сирий=з["драп"], сценарій=з["сценарій"], паспорт=з["паспорт"],
          намір=з["паспорт"]["намір"], **з["мірки"])
усі = [o for р in json.loads(B.палітри(вх))["основи"].values() if isinstance(р, list) for o in р]
о = next(o for o in усі if o.get("ключ", "").startswith("хвойний·тепла·32·середні"))
вх.update(гілка=3, каталог=Ф.каталог_на_диску("каталог_повний.xml"),
          кеш_кольорів=os.path.join(tempfile.gettempdir(), "кеш_живого_шляху.json"),
          вибір_кольору=dict(база=о["ключ"], база_hex=о["hex"], база_тип="колір", насиченість="середні",
                             схема="приглушена_комплементарна", схему_обрала_вона=True))
if not os.path.exists(вх["кеш_кольорів"]):
    json.dump({}, open(вх["кеш_кольорів"], "w"))
B.виклик("запити", json.dumps(dict(вх, пакети=1), ensure_ascii=False))
from міст_пакет import _КЕШ_ПАКЕТА, _ОСТАННІЙ_ПАКЕТ
пак = _КЕШ_ПАКЕТА[_ОСТАННІЙ_ПАКЕТ[-1]]
сп = {с["роль"]: с for с in пак["_спец_слоти"]["_сім_ї"]}
for с in пак["_схема_великі"]["сім_ї"]:
    зр = сп[с["роль"]].get("зразок")
    L, C, h = cs.lch(cs.hx(зр))
    вікно = lambda w: V.вікно_вжитку(V.слово_крамниці(w)["ім"])
    так = lambda в: в[0] <= L <= в[1] and в[2] <= C <= в[3] and (в[4] is None or V._у_дузі(h, в[4]))
    print("%-10s зразок %s L*%2.0f C*%2.0f h%3.0f · слова добору %s · вікно вжитку накриває зразок: %s"
          % (с["роль"], зр, L, C, h, с["слова"], [так(вікно(w)) for w in с["слова"]]))
print("стилістці (_схема_її):", пак["_схема_її"]["families"])
