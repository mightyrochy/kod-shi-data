# -*- coding: utf-8 -*-
"""Рядок 48: той самий клатч у картках рук 1 і 2 одного прогону. `різноманітність`
судить лише 10 варіантів ОДНІЄЇ руки — картки рук 1/2 складаються в РІЗНИХ
вердиктах і одна одної не бачать; `pipeline.повтор_прогону` веде спільний реєстр
прогону (той самий сід), у якому K-VAR-01 бачить повтор МІЖ руками."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import pipeline as PL

річ = lambda і, с, н: dict(id=і, слот=с, назва=н)
реєстр_прогону = {}

# рука 1 бере клатч b1 і сукню d1 — перша в цьому прогоні, повтору бути не може
зн1 = PL.повтор_прогону(реєстр_прогону, "1", [річ("b1", "сумка", "Клатч сірий"),
                                              річ("d1", "сукня", "Сукня міді")])
print("рука 1 (перша): %s" % (зн1 or "нема повтору (правильно)"))
assert зн1 is None

# рука 2 бере ТОЙ САМИЙ клатч b1 (інша сукня) — повтор МІЖ картками
зн2 = PL.повтор_прогону(реєстр_прогону, "2", [річ("b1", "сумка", "Клатч сірий"),
                                              річ("d2", "сукня", "Інша сукня")])
print("рука 2 (той самий клатч): %s" % (зн2["суть"] if зн2 else "НЕМА (провал)"))
assert зн2 and зн2["правило"] == "K-VAR-01" and зн2["речі"] == ["b1"]

# рука 3 бере ІНШУ сумку — це вибір, не повтор
зн3 = PL.повтор_прогону(реєстр_прогону, "3", [річ("b2", "сумка", "Шопер бежевий")])
print("рука 3 (інша сумка): %s" % (зн3 or "нема повтору (правильно)"))
assert зн3 is None
