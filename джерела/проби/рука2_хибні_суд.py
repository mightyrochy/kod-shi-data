import pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import правило_руки2 as П, формальність as Ф, внутрішня_мова as В, composer as К
сц = Ф.сценарій(місце='ресторан', нагода='побачення', смуга=[4, 6])
assert сц['діапазон'] == (4.0, 6.0) or list(сц['діапазон']) == [4.0, 6.0]
with П.зламано(П.ЗА_ІД['K-KOH-02']['коди']):
    е = [dict(річ='верх-фікстура', слот='верх', формальність=4), dict(річ='низ-фікстура', слот='низ', формальність=5)]
    з = Ф.формальність_образу(е, сц)
    активні = [x for x in з if x.get('правило') == 'K-KOH-02' and x.get('ремонт_заяви')]
    assert активні and активні[0]['сила_нп'] > 0 and активні[0]['ремонт_заяви'][0]['values']['band'] == [3.0, 3.0]
    assert П.хибний_щабель((3, 5), (4, 6), (3, 3)) is False
    assert П.хибний_щабель((2, 3), (4, 6), (3, 3)) is True
    assert П.сусідня_смуга((1, 10)) is None
    assert П.сусідня_смуга((1, 6)) == (7, 7)
    кат = [dict(id='нормальна', слот='верх', формальність=4), dict(id='хибна', слот='верх', формальність=3), dict(id='невідома', слот='верх')]
    пул, геть, _ = К._поза_сценою(кат, dict(ошатність=[4, 6]))
    assert {r['id'] for r in пул} == {'хибна', 'невідома'} and [r['id'] for r in геть] == ['нормальна']
    assert П.вхід(П.ЗА_ІД['K-KOH-02'], dict(сценарій=dict(ошатність=[1, 10])))[0] is False
with П.зламано(П.ЗА_ІД['K-KOH-02']['коди']):
    з = Ф.формальність_образу([dict(річ='невідомий-верх', слот='верх'), dict(річ='невідомий-низ', слот='низ')], сц)
    assert not П.тінь() and any(x.get('без_входу') and x.get('сила_нп') == 0 for x in з)
with П.зламано(П.ЗА_ІД['K-CRA-01']['коди']):
    адресат = dict(id='третя-фікстура'); образ = ['верх-фікстура', 'низ-фікстура', адресат['id']]
    зн = П.хибна_знахідка('K-CRA-01', [адресат], 'require_third_piece', 'omit_third_piece', 'remove_items', В.заява('remove_this_item'), образ)
