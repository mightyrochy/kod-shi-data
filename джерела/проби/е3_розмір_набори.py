    for о in ("52-18-140", "48-16-135", "55/20", "60", "без розміру", (50, 14, 140), 70, 58.5):
        yield dict(id="e%s" % (о,), слот="окуляри", оправа=о)
    for о in range(480, 640, 5):
        yield dict(id="h%d" % о, слот="головний_убір", обхват_голови_см=о / 10)
    for п in (None, "від шва великого пальця"):
        yield dict(id="g%s" % п, слот="рукавички", bl="16", bl_походження=п)
    for п in (None, "вузька", "середня", "широка"):
        for р in (None, "маломірить", "великомірить", "повномірить", "інше"):
            yield dict(id="w%s%s" % (п, р), слот="взуття", повнота=п, розмірність=р)
    yield dict(id="t", слот="годинник", lug_мм=46)


