import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import pipeline as П
к = {"сукня": [dict(id="ж-1@к.ua", назва="сукня міді")], "прикраси": [dict(id="ж-4@к.ua", назва="сережки")],
     "взуття": [dict(id="ж-2@в.ua", назва="лофери"), dict(id="ж-3@в.ua", назва="човники")]}
ном = П.номери_речей(к)[0]; н = lambda і: "#%d·%s" % ном[і]
о1, о2 = [н("ж-1@к.ua"), н("ж-2@в.ua"), н("ж-4@к.ua")], [н("ж-1@к.ua"), н("ж-3@в.ua"), н("ж-4@к.ua")]
