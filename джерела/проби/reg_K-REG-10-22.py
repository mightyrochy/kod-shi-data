# -*- coding: utf-8 -*-
"""Реєстр за реєстром на живому каталозі: скільки речей і чим упізнані. Запуск із
теки `джерела`: `python3 проби/reg_K-REG-10-22.py`.

Це відповідь на «без сліду» з аудиту поіменно: для кожного з тринадцяти або
число речей і слова, якими вони впізнані, або чесне «входу нема» з назвою того,
чого бракує. Жоден реєстр не має права зникнути з цього списку мовчки."""
import sys, pathlib, collections
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import feed as Ф, реєстри as РЕ

офери, _ = Ф.читати_yml(Ф.каталог_на_диску("каталог_повний.xml"))
за, слова, зразок = collections.Counter(), collections.defaultdict(collections.Counter), {}
розпізнано = 0
for o in офери:
    в = РЕ.реєстр_речі(o)
    if not в["розпізнано"]:
        continue
    розпізнано += 1
    for k, ч in в["збіги"].items():
        за[k] += 1
        зразок.setdefault(k, (o["назва"] or "")[:52])
        for м in ч:
            слова[k][м] += 1

print("каталог: %d речей · хоч один реєстр розпізнано на %d (%.1f %%)"
      % (len(офери), розпізнано, 100.0 * розпізнано / len(офери)))
мертві = []
for к, д in РЕ.РЕЄСТРИ.items():
    топ = ", ".join("%s %d" % x for x in слова[к].most_common(3)) or "—"
    print("%s %-14s %5d  %-34s %s" % (д["ід"], к, за[к], топ, зразок.get(к, "")))
    if not за[к]:
        мертві.append(д["ід"])
print("реєстрів без жодної речі в каталозі:", мертві or "жодного")
assert not мертві, "реєстр без входу мусить бути названий, а не мовчати: %s" % мертві
