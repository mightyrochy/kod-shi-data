# -*- coding: utf-8 -*-
"""Рядок 131 + правка куратора 23.09 («без прибитих станів гілок»): перша версія
проби перевіряла КОНКРЕТНІ гілки за іменем («134 — незлита робота») — це стан на
момент писання, а не інваріант; після злиття #220/#224 вона впала б на main.
Тут — три інваріанти, байдужі до того, яка саме гілка й коли злилась, на вибірці
з 15 найсвіжіше торкнутих origin/* (бере сама git, не список імен у коді).
`python3 проби/hilky_131.py` (з теки `джерела`)."""
import subprocess, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "прилади"))
import datetime as _dt
import гілки_незлиті as Г

вибірка = subprocess.run(["git", "-c", "core.quotepath=false", "for-each-ref", "refs/remotes/origin",
                          "--sort=-committerdate", "--format=%(refname:short)", "--count=15"],
                          capture_output=True, text=True, encoding="utf-8", check=True)
гілки = [г for г in вибірка.stdout.split() if г not in ("origin/HEAD", Г.ГОЛОВНА)]
тепер = _dt.datetime.now(_dt.timezone.utc)
мілкий = Г.мілкий_клон()
результати = {г: Г.проаналізувати(г, тепер, мілкий) for г in гілки}

екрановано = [(г, ф) for г, р in результати.items() for ф in р["відмінні_файли"] + р["переписані_main"]
              if "\\" in ф or ф.startswith('"')]
предки = [г for г in гілки if Г.є_предком_main(г)]
без_предка = [г for г in гілки if Г.спільний_предок(г) is None]

print("мілкий клон: %s · вибірка %d гілок · предків main %d · без спільного предка %d"
      % (мілкий, len(гілки), len(предки), len(без_предка)))
print("екранованих кириличних шляхів: %d" % len(екрановано))
assert not екрановано, "core.quotepath не спрацював: %r" % екрановано

for г in предки:
    assert результати[г]["клас"] == "без_вмісту", "%s — предок main, а клас %s" % (г, результати[г]["клас"])
print("інваріант «предок main → без_вмісту»: %s" % ("БЕЗ ВХОДУ (нема предків у вибірці)" if not предки else "OK"))

for г in без_предка:
    assert результати[г]["клас"] == "не_можу_судити", "%s без спільного предка, а клас %s" % (г, результати[г]["клас"])
print("інваріант «без предка → не_можу_судити»: %s" % ("БЕЗ ВХОДУ (нема таких у вибірці)" if not без_предка else "OK"))
