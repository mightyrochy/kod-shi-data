# -*- coding: utf-8 -*-
"""Рядок 131: скільки origin/* гілок у кожному класі приладу `гілки_незлиті.py`,
і що жоден кириличний шлях не прийшов екранованим (той самий клас поломки, що
рядок 130 — `core.quotepath`). `python3 проби/hilky_131.py` (з теки `джерела`)."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "прилади"))
import datetime as _dt
import гілки_незлиті as Г

тепер = _dt.datetime.now(_dt.timezone.utc)
результати = [Г.проаналізувати(гілка, тепер) for гілка in Г.гілки_на_огляд()]
незлиті = [р for р in результати if р["клас"] == "незлита_робота"]
без_вмісту = [р for р in результати if р["клас"] == "без_вмісту"]
екрановано = [(р["гілка"], ф) for р in незлиті for ф in р["відмінні_файли"] if "\\" in ф or ф.startswith('"')]

print("оглянуто гілок %d · незлита робота %d · без власного вмісту %d"
      % (len(результати), len(незлиті), len(без_вмісту)))
print("екранованих кириличних шляхів серед відмінних файлів: %d" % len(екрановано))
assert len(результати) == len(незлиті) + len(без_вмісту), "клас губить гілку"
assert not екрановано, "core.quotepath не спрацював: %r" % екрановано

сумка = next((р for р in незлиті if р["гілка"] == "origin/claude/misce-sumky-129"), None)
if сумка:
    кир = [ф for ф in сумка["відмінні_файли"] if ф.startswith("джерела/аксесуари_структура.py")]
    print("misce-sumky-129: джерела/аксесуари_структура.py серед відмінних — %s" % bool(кир))
    assert кир, "кириличний файл 129 не потрапив у список відмінних"
else:
    print("misce-sumky-129: гілки нема серед оглянутих [БЕЗ ВХОДУ]")
