"""Рядок 131 + правка куратора (PR #222): мілкий клон хмарної сесії (глибина 50)
робив `git cherry` ненадійним для гілок без спільного предка в отриманій історії —
третій клас «не можу судити» ловить це. Три іменні гілки замість повного огляду
227+ (куратор: повний прогін на глибокому клоні — 946 с; тут — секунди), по одній
на клас. `python3 проби/hilky_131.py` (з теки `джерела`)."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "прилади"))
import datetime as _dt
import гілки_незлиті as Г

ЗА_ІМЕНАМИ = ["claude/misce-sumky-129", "claude/verdykt-fail-134", "наряд/С-01"]
тепер = _dt.datetime.now(_dt.timezone.utc)
мілкий = Г.мілкий_клон()
гілки = Г.гілки_на_огляд(фільтр=ЗА_ІМЕНАМИ)
результати = [Г.проаналізувати(г, тепер, мілкий) for г in гілки]
за_клас = {р["гілка"]: р["клас"] for р in результати}
екрановано = [(р["гілка"], ф) for р in результати for ф in р["відмінні_файли"] if "\\" in ф or ф.startswith('"')]

print("мілкий клон: %s · гілок знайдено %d/%d" % (мілкий, len(гілки), len(ЗА_ІМЕНАМИ)))
for г, к in sorted(за_клас.items()):
    print("  %-40s %s" % (г[len("origin/"):], к))
print("екранованих кириличних шляхів: %d" % len(екрановано))
assert not екрановано, "core.quotepath не спрацював: %r" % екрановано

assert за_клас.get("origin/claude/misce-sumky-129") == "без_вмісту", \
    "129 злилась у main (#219) — мала бути «без власного вмісту»"
assert за_клас.get("origin/claude/verdykt-fail-134") == "незлита_робота", \
    "134 у роботі, спільний предок є — мала лишитись «незлита робота»"
assert за_клас.get("origin/наряд/С-01") == "не_можу_судити", \
    "С-01 без спільного предка в цій історії — cherry тут не суддя, а не «незлита робота»"
