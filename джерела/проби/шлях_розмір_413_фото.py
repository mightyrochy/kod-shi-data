# -*- coding: utf-8 -*-
"""Складання (показ.html:8060) шле текст `r.руки[рука]` РАЗОМ із її закріпленими
фото base64 (`фотоЗакріпленихП`, показ.html:4484-4489) — міст рахує розмір усього
`тіло.messages` (worker.js:283-285), не лише тексту. Факт власника 25.09
(verdykty-…-2012.json): запит 428155 симв, HTTP 413, а текст цього ж вердикта —
119893 симв (`етапи.виклики[0].запит.символів`) — фото додали ще ~308 тис. симв.
Проба рахує текст РЕАЛЬНИМ пайплайном (bridge) і зіставляє зі стелею. Друкує факт.
Запуск: cd джерела && python3 проби/шлях_розмір_413_фото.py"""
import json, os, re, sys
_КОРІНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _КОРІНЬ)
import bridge as B, feed as Ф
вх = json.load(open(os.path.join(_КОРІНЬ, "стенд_вх.json"), encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
текст = r["руки"]["1"]
показ = open(os.path.join(_КОРІНЬ, "показ.html"), encoding="utf-8").read()
worker = open(os.path.join(_КОРІНЬ, "worker.js"), encoding="utf-8").read()
стеля_мосту = int(re.search(r"СТЕЛЯ_ВХОДУ_СИМВ\s*=\s*(\d+)", worker).group(1))
макс_фото = int(re.search(r"МАКС_СИМВОЛІВ_ФОТО\s*=\s*(\d+)", показ).group(1))
# факт власника 25.09: текст цього самого кроку на живому прогоні — 119893
текст_владника, реальний_запит = 119_893, 428_155
фото_в_реальному = реальний_запит - текст_владника
print("стеля мосту (worker.js:50):", стеля_мосту, "симв")
print("стеля одного фото (показ.html):", макс_фото, "симв")
print("складання, текст пулу зараз (bridge, каталог_повний):", len(текст), "симв")
print("складання, текст пулу у владника 25.09 (з файлу вердиктів):", текст_владника, "симв")
print("владник: текст %d + фото %d = %d симв (> стеля %d → HTTP 413)"
      % (текст_владника, фото_в_реальному, реальний_запит, стеля_мосту))
запас_1_фото = стеля_мосту - (макс_фото + len(текст))
print("1 її фото на стелі (%d) + поточний текст (%d) = %d — запас до стелі мосту: %d симв (%.1f%%)"
      % (макс_фото, len(текст), макс_фото + len(текст), запас_1_фото, 100 * запас_1_фото / стеля_мосту))
print("2 її фото на стелі (%d) + поточний текст (%d) = %d — понад стелю мосту: %s"
      % (2 * макс_фото, len(текст), 2 * макс_фото + len(текст), 2 * макс_фото + len(текст) > стеля_мосту))
assert фото_в_реальному <= 2 * макс_фото, "владникові фото мали б лізти у 2 стелі"
assert 2 * макс_фото + len(текст) > стеля_мосту
assert 0 < запас_1_фото < 0.1 * стеля_мосту, "навіть 1 фото на стелі лишає запас <10%"
