# -*- coding: utf-8 -*-
"""Промпт складання рук 1–2 до/після П-2 на сирих прогонах ноутбука (ПАКЕТ_V1 → ОБРАЗИ_V1).

Ті самі дані (обʼєкт старого промпта) крізь `пакет_моделі.промпт_складання`: символи й токени
gemma (GEMMA_TOKENIZER — шлях до tokenizer.json) старого й нового і які факти старого не дійшли.
Умови, що доти стояли реченнями `завдання.вимоги` (недосяжні полюси, пальто), беруться з тих
речень у поля пакета — так їх кладе продукт. Що не йде свідомо — `дріт_факти.СВІДОМО`.
Запуск: cd джерела && GEMMA_TOKENIZER=… python3 проби/промпт_складання.py"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import дріт_факти as Ф, пакет_моделі as ПМ
разом = [0, 0]
for ім, п in Ф.сирі("*ПАКЕТ_V1_ОБРАЗИ_V1*"):
    ст = json.loads(п); в = ст["завдання"].get("вимоги") or []
    пак = Ф.з_осями({к: v for к, v in ст.items() if к != "завдання"})
    пак["завдання"] = {"образів": ст["завдання"]["образів"], "відповідь": "ОБРАЗИ_V1", "мова_тексту": "English"}
    м = next((re.findall(r"«([^»]+)» — ([^;]+?)\.?(?:;|$)", р.split(": ", 1)[1]) for р in в if "пул дати не може" in р), [])
    if м:
        пак["полюси_недосяжні"] = [dict(ід=і, чому=ч) for і, ч in м]
    if any("Надворі холодно" in р for р in в):
        пак["обмеження"] = dict(пак.get("обмеження") or {}, пальто=True)
    н = ПМ.промпт_складання(пак)
    без = Ф.загублено(dict(ст, **({"полюси_недосяжні": пак["полюси_недосяжні"]} if м else {})), н)
    разом[0] += 1; разом[1] += len(без)
    print("%-52s було %6d симв / %5s ток → стало %6d симв / %5s ток · речей %d · загублено: %s"
          % (ім[:52], len(п), Ф.ток(п), len(н), Ф.ток(н), len(json.loads(н)["pool"]), без[:6] or "нічого"))
print("прогонів %d, загублених фактів разом %d · свідомо не йде: %s" % (разом[0], разом[1], "; ".join(
    "%s — %s" % (к, ч) for к, ч in Ф.СВІДОМО.items() if к in ("може_стати", "рядок", "опис"))))
