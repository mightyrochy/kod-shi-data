# -*- coding: utf-8 -*-
"""B: одна межа нейтралі. bridge.палітри типувала дефолтну базу порогом C*<8,
bases.за_родом і реєстр (neutral_C, K-COL-06) ділять по 12. Тепер усі три
читають реєстр. Факти: (1) синтетична клітинка C*=10 у палітри → «нейтраль»;
(2) на трьох профілях жодна клітинка ряду «нейтралі» не стає hue-якорем."""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import colorspace as cs, bridge as B, bases as ОС, реєстр_правил as Р
print("межа: реєстр neutral_C=%s, bases.АХРОМАТИЧНА_МЕЖА=%s" % (Р.C["neutral_C"], ОС.АХРОМАТИЧНА_МЕЖА))
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
_справжня = B._основи
def _підміна(F, **kw):
    о = _справжня(F, **kw)
    о["рекомендовані"] = [dict(о["рекомендовані"][0], hex="#b8a9a0", осі=dict(о["рекомендовані"][0]["осі"], Cstar=10.0))]
    return о
B._основи = _підміна
р = json.loads(B.палітри(json.dumps(вх, ensure_ascii=False)))
B._основи = _справжня
print("синтетична дефолтна база C*=10.0 → база_тип=%s (до правки: «колір» → hue-якір)" % р["вибір_кольору"]["база_тип"])
ПРОФІЛІ = [("1", вх["шкіра"], вх["волосся"][0], вх["очі"]), ("2", "#eec2b0", "#e8d5b0", "#8a9bb0"), ("3", "#96632f", "#3a2a1a", "#4a3222")]
якорів, клітинок = 0, 0
for н, шк, вл, оч in ПРОФІЛІ:
    d = dict(вх, шкіра=шк, волосся=[вл], очі=оч)
    F, T, зріст, kw = B._збірка(d); якір = B._якір(d)
    о = B._основи(F, intent="conventional")
    для = о["нейтралі"] + [x for x in о["інші"] if x["осі"]["Cstar"] < ОС.АХРОМАТИЧНА_МЕЖА]
    for x in для:
        тип = "нейтраль" if x["осі"]["Cstar"] < ОС.АХРОМАТИЧНА_МЕЖА else "колір"
        п = B._пакет(F, T, зріст, kw, якір, "conventional", None,
                     dict(база=x["ключ"], база_hex=x["hex"], база_тип=тип), None)
        сп = п["палітри"]["розвилка"][0]["спец"]
        клітинок += 1; якорів += (сп.get("якір_джерело") == "обраний")
    print("профіль %s: клітинок ряду «нейтралі» %d (у ряду %d), з них hue-якорем стали: %d"
          % (н, len(для), len(о["нейтралі"]), якорів))
print("разом: %d нейтральних клітинок, hue-якорем стало %d" % (клітинок, якорів))
