"""Метал інтервалу: суд і палітра погоджуються без вигаданої точки. Метал — код матеріалу (`palettes.колір_металу`,
крок 30 кореня Річ-колір-межі): колір речі (вікно слова чи точка) його не міняє, обруч — не метал; вставки (`колір_вставки`) код не має (14415)."""
import sys
sys.path.insert(0, ".")
import palettes as П, verify as В, фід_збагачення as З, колір_річ as К
from суд_від_моделі import бюджет_і_відлуння, _метал_точки


def головна():
    """Надрукувати рішення для золота, обруча та невідомого кольору."""
    р = dict(id="золоте-намисто", слот="намисто", тип="намисто", метал="золото",
             колір_тип="інтервал", lab=None,
             колір_не_вимір=З.не_вимір_кольору(В.вікно_вжитку("бежевий"), "бежевий", "shop_word"))
    хибні = [з for з in бюджет_і_відлуння([р]) if з.get("правило") == "K-COL-05"]
    метал = bool(_метал_точки((dict(id=р["id"]), "намисто", None, None, None), {р["id"]: р}))
    print("Метал палітри:", П.колір_металу(р), "суду:", метал, "тон:", П.метал_речі(р), "K-COL-05:", len(хибні))
    assert К.точка_кольору(р) is None and метал == П.колір_металу(р) is True and П.метал_речі(р) == "золото" and not хибні
    for інша in (dict(р, колір_тип="невідомо", колір_не_вимір=None), dict(р, слот="прикраси", тип="обруч")):
        assert not _метал_точки((інша, інша["слот"], None, None, None))
    for lab in ((70, 15, 40), (80, 0, 0), (50, 60, 30)):
        for метал_ in ("золото", "срібло", None):
            вимір = dict(слот="намисто", lab=lab, метал=метал_)
            assert bool(_метал_точки((вимір, "намисто", *lab))) == bool(П.метал_речі(вимір)) == bool(метал_)


if __name__ == "__main__":
    головна()
