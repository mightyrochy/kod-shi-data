"""Метал інтервалу: суд і палітра погоджуються без вигаданої точки."""
import sys
sys.path.insert(0, ".")
import palettes as П, verify as В, фід_збагачення as З, колір_річ as К
from суд_від_моделі import бюджет_і_відлуння, _метал_точки


def головна():
    """Надрукувати рішення для золота, вставки, обруча та невідомого кольору."""
    р = dict(id="золоте-намисто", слот="намисто", тип="намисто", метал="золото",
             колір_тип="інтервал", lab=None,
             колір_не_вимір=З.не_вимір_кольору(В.ЛЕКСИКОН["золотий"], "золотий", "shop_word"))
    хибні = [з for з in бюджет_і_відлуння([р]) if з.get("правило") == "K-COL-05"]
    метал = bool(_метал_точки((dict(id=р["id"]), "намисто", None, None, None), {р["id"]: р}))
    print("Метал палітри:", П.колір_металу(р), "суду:", метал, "K-COL-05:", len(хибні))
    assert К.точка_кольору(р) is None and метал == П.колір_металу(р) and not хибні
    for інша in (dict(р, колір_тип="невідомо"), dict(р, слот="прикраси", тип="обруч"),
                  dict(р, колір_вставки=[dict(lab=(50, 60, 30), частка=1)])):
        assert not _метал_точки((інша, інша["слот"], None, None, None))
    for lab in ((70, 15, 40), (80, 0, 0), (50, 60, 30)):
        вимір = dict(слот="намисто", lab=lab)
        assert bool(_метал_точки((вимір, "намисто", *lab))) == bool(П.метал_речі(lab, "намисто"))


if __name__ == "__main__":
    головна()
