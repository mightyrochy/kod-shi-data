import sys, pathlib, json
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B

вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
хустки = [c for c in кат.values() if c["слот"] == "шарф"]
з_форматом = [c for c in хустки if c.get("розмір_см")]
print("хусток у каталозі пакета: %d, із квадратним форматом: %d — %s"
      % (len(хустки), len(з_форматом), sorted(c["розмір_см"] for c in з_форматом)))
assert з_форматом, "формат не доїхав до запису каталогу — ворота знов сліпі"
мала = min(з_форматом, key=lambda c: c["розмір_см"])
база = [next(c for c in кат.values() if c["слот"] == сл) for сл in ("сукня", "взуття")]
ід = [c["id"] for c in база + [мала]]
print("хустка образу:", мала["назва"][:44], "· формат", мала["розмір_см"], "см")
вд = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
о = ((вд.get("вердикт") or {}).get("образи") or [{}])[0]
з = next((z for z in (о.get("знахідки") or []) if z["правило"] == "K-CRA-12"), None)
print("K-CRA-12 у вердикті:", "НЕМА" if not з else
      "%s %.2f · %s" % (з["сила"], з["сила_нп"], з["суть"][:58]))
print("  речі рядка:", (з or {}).get("речі"), "· регістр", (з or {}).get("регістр"))
