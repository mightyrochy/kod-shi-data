# -*- coding: utf-8 -*-
"""Рядок 164: скільки важить промпт виклику 0 на довгій розмові — до і після ковзного вікна.
«До» = те саме, що до правки: вікно на всю стрічку (`ВІКНО_РОЗМОВИ` у нескінченність), тобто
кожна репліка дослівно й без зведення. Чат не обривається ні до, ні після (ЧАТ_ЛІМІТ_П той самий).
Токени: `TOKENIZER=<шлях до tokenizer.json>` — інакше символи й оцінка (кирилиця в JSON ≈ 2.6 симв/ток).
Запуск: cd джерела && python3 проби/вікно_розмови_164.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import паспорт_нагоди as П

Т = None
if os.environ.get("TOKENIZER"):
    from tokenizers import Tokenizer; Т = Tokenizer.from_file(os.environ["TOKENIZER"])
ток = lambda s: len(Т.encode(s, add_special_tokens=False).ids) if Т else round(len(s) / 2.6)
СЦ = {"нагода": "побачення", "місце": "ресторан_районний"}
# репліки живої довжини: її — ~190 символів, стилістки — ~150 (запис стенда 26.09)
ходи = lambda n: [{"хто": ("людина" if i % 2 == 0 else "ші"),
                   "текст": ("мені треба образ, і я хочу сказати ще ось що про цей вечір " * 3)[:190 - i % 7]
                            if i % 2 == 0 else ("гарно, а тепер розкажи ще трохи про нагоду " * 3)[:150]}
                  for i in range(n)]
print("%6s %9s %8s  %10s %9s  %s" % ("ходів", "симв до", "ток до", "симв після", "ток після", "поля розмови після"))
for n in (2, 10, 30, 100):
    ціле, П.ВІКНО_РОЗМОВИ = П.ВІКНО_РОЗМОВИ, 10 ** 9
    до = П.промпт_паспорта(СЦ, "", історія=ходи(n))
    П.ВІКНО_РОЗМОВИ = ціле
    після = П.промпт_паспорта(СЦ, "", історія=ходи(n))
    д = json.loads(після)
    поля = "розмова %d" % len(д.get("розмова") or [])
    if д.get("розмова_раніше"):
        поля += " · раніше: ходів %d, її реплік %d" % (д["розмова_раніше"]["ходів"],
                                                       len(д["розмова_раніше"]["її_слова"]))
    print("%6d %9d %8s  %10d %9s  %s" % (n, len(до), ток(до), len(після), ток(після), поля))
    if n >= 30 and len(після) >= len(до):
        print("✗ вікно не зменшило промпт на %d ходах" % n); sys.exit(1)
# СТЕЛЯ, А НЕ ПРОСТО «МЕНШЕ»: щойно зведення повне (12 її реплік), 300 ходів важать як 100
_100, _300 = (len(П.промпт_паспорта(СЦ, "", історія=ходи(n))) for n in (100, 300))
print("стеля: 100 ходів %d симв, 300 ходів %d симв — різниця %+d" % (_100, _300, _300 - _100))
if _300 > _100 + 20:
    print("✗ промпт і далі росте з розмовою"); sys.exit(1)
print("✓ промпт виклику 0 має стелю; розмова не обрізана (ЧАТ_ЛІМІТ_П не змінено)")
