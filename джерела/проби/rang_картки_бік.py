# -*- coding: utf-8 -*-
"""П.4 наряду: вісь тону з фото стиснена (не міняти), але з картками біля обличчя
вона ОЖИВАЄ — і в правильний бік. До правки з картками «срібло/холодні/холодний»
перший рекомендований колір був персиковий (h 30°): формула тепла шкіри,
розтягнута на тканину, читала все понад 75° як «тепле»."""
import sys, os, json, math
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import colorspace as cs, bridge as B, bases as ОС
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
F = cs.features(cs.hx(вх["шкіра"]), cs.hx(вх["волосся"][0]), cs.hx(вх["очі"]))
КАРТКИ = {
    "фото (без карток)": (None, 0),
    "золото / теплі / теплий білий": (dict(метал="золото", нейтраль="теплі", білий="теплий"), +1),
    "срібло / холодні / холодний білий": (dict(метал="срібло", нейтраль="холодні", білий="холодний"), -1),
}
топ8 = {}
for назва, (сз, бік) in КАРТКИ.items():
    о = B._основи(F, самозвіт=сз, intent="conventional")
    т = о["пояснення"]["температура"]
    кол = [x for x in о["рекомендовані"] if x["осі"]["Cstar"] >= ОС.АХРОМАТИЧНА_МЕЖА]
    свої = [x for x in кол if бік == 0 or ОС._бік_тону(cs.lch(cs.hx(x["hex"]))[2]) * бік >= 0]
    топ8[назва] = [x["ключ"] for x in кол[:8]]
    print("== %s: позиція %+.2f, впевненість %.2f (%s)" % (назва, т["позиція"], т["впевненість"], т["джерело"]))
    print("   рекомендованих кольорів %d, на боці людини %d; чутливість тону %.4f/ΔE00"
          % (len(кол), len(свої), о["пояснення"]["чутливість_ΔE00"]["тон"]))
    for x in кол[:3]:
        h = cs.lch(cs.hx(x["hex"]))[2]
        print("   %.3f %s h=%5.1f бік=%+.2f s_H=%.2f %s" % (x["бал"], x["hex"], h, ОС._бік_тону(h), x["осі"]["H"], x["ключ"]))
н = list(топ8)
print("топ-8 кольорів: фото ≠ теплі картки: %s; теплі ≠ холодні: %s"
      % (топ8[н[0]] != топ8[н[1]], топ8[н[1]] != топ8[н[2]]))
