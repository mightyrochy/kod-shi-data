# -*- coding: utf-8 -*-
"""Форми на «ви» в текстах картки, які прийняв мовний шар, на сирих записах VIDPOVIDI (рядок 5983).

Запуск: `python3 проби/мова_ти_5983.py <тека живого прогону>`; без виклику моделі. Друкує запис і форми
та підсумок: тексти, тексти без відповіді (лишились вхідними), форм на «ви». Лічба — мірило проби, не код продукту."""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import мовний_шар as М

_Л = "а-яіїєґ'’"
ФОРМИ = re.compile(r"(?<![%s])(ви|вас|вам|вами|ваш\w*|\w{3,}(?:іть|ійте|айте|яйте|уйте|юйте|ьте|ете|єте|ите|їте))"
                   r"(?![%s])" % (_Л, _Л), re.I)
НЕ_ФОРМИ = {"навіть", "відкрите", "закрите", "вшите", "покрите", "вишите", "зшите", "розкрите"}

if __name__ == '__main__':
    тека, текстів, без, ви = Path(sys.argv[1]), 0, 0, 0
    for файл in sorted(тека.rglob('*_мовний_шар.txt')):
        сирий = файл.read_text(encoding='utf-8')
        if '\nТЕКСТИ:\n' not in сирий:
            continue
        розмітка, _ = json.JSONDecoder().raw_decode(сирий.split('\nТЕКСТИ:\n', 1)[1].lstrip())
        розмітка = [dict(р, ключ=str(р['н'])) for р in розмітка]
        вихід = М.прийняти(розмітка, re.split(r'── ВІДПОВІДЬ[^\n]*\n', сирий, maxsplit=1)[1])
        форми = [м.group(1) for т in вихід['тексти'].values() for м in ФОРМИ.finditer(т)
                 if м.group(1).lower() not in НЕ_ФОРМИ]
        текстів, без, ви = текстів + len(розмітка), без + len(вихід['без_відповіді']), ви + len(форми)
        if форми:
            print(f'{файл.relative_to(тека)}: {форми}')
    print(f'Разом: текстів {текстів}, без відповіді {без}, форм на «ви» {ви}')
