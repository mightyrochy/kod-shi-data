# -*- coding: utf-8 -*-
"""Рядок 47: дві пари сережок в одному образі — «Malachite» (слот «сережки») і
«Придане» (слот «прикраси», бо назва не збіглася з жодним ключем feed збору) —
лічба «по одній речі на слот» їх не бачить: слоти різні, дублю не видно. ДО
ПРАВКИ жодного блокера; ПІСЛЯ — лічба веде сім'ю (`pipeline._сім_я_слота`)."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import pipeline as PL

річ = lambda і, с, н: dict(id=і, слот=с, назва=н, тип=н)
БАЗА = [річ("d1", "сукня", "Сукня міді"), річ("s1", "взуття", "Човники")]

# а) дві пари сережок у РІЗНИХ під-слотах — та сама сім'я
об_а = БАЗА + [річ("e1", "сережки", "Сережки Malachite"),
               річ("e2", "прикраси", "Сережки золотисті Придане")]
бл_а = PL.структура_образу([dict(r) for r in об_а], None, {"нагода": "побачення"})
знайдено_а = [b for b in бл_а if "у сім'ї «сережки» 2 речі" in b]
print("а) сережки в двох під-слотах: %s" % (знайдено_а[0] if знайдено_а else "БЛОКЕРА НЕМА (провал)"))
assert знайдено_а, "дві пари сережок у різних під-слотах мають дати блокер сім'ї"

# б) сережки + каблучка — РІЗНІ сім'ї, блокера бути не повинно
об_б = БАЗА + [річ("e1", "сережки", "Сережки Malachite"),
               річ("r1", "прикраси", "Каблучка срібна")]
бл_б = PL.структура_образу([dict(r) for r in об_б], None, {"нагода": "побачення"})
знайдено_б = [b for b in бл_б if "сім'ї" in b]
print("б) сережки + каблучка: %s" % (знайдено_б or "блокера нема (правильно)"))
assert not знайдено_б, "сережки й каблучка — різні сім'ї, блокер сім'ї тут зайвий"
