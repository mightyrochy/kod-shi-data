"""Звірити кожну погодну знахідку з двох знімків; друк таблиці змін ваги."""
import collections, gzip, json, sys


def main():
    """Звірити склад, силу, сиру вагу й вагу після спільної стелі."""
    def читати(шлях):
        with gzip.open(шлях, 'rt', encoding='utf-8') as ф:
            return json.load(ф)
    до, після = map(читати, sys.argv[1:3])
    assert len(до) == len(після), (len(до), len(після))
    зміни, ефективні = collections.Counter(), collections.Counter()
    for д, п in zip(до, після):
        assert д[:6] == п[:6], (д, п)
        if д[6] != п[6]:
            зміни[д[2], д[6], п[6]] += 1
        if д[7] != п[7]:
            ефективні[д[2], д[7], п[7]] += 1
    print('знахідок', len(до), 'склад і сила тотожні; сирих змін', sum(зміни.values()),
          'після стелі', sum(ефективні.values()))
    print('| Правило | ДО | ПІСЛЯ | Кількість | Чому |')
    print('|---|---|---|---|---|')
    for (правило, було, стало), кількість in sorted(зміни.items(), key=str):
        print('| %s | %s | %s | %s | стеля ефективної категорії в конструкторі |'
              % (правило, було, стало, кількість))
    print('Ефективні зміни:', dict(ефективні))
    assert not ефективні, dict(ефективні)


if __name__ == '__main__':
    main()
