# -*- coding: utf-8 -*-
"""K-ACC-07 (хустка ПЕРЕВИЗНАЧАЄ приобличчеве поле — вона не оздоба).

ДО ПРАВКИ умова на живому вході була завжди хибна.
`носій_приобличчевого_поля` вимагає `р["місце"] in ("шия","волосся","плечі")`, а
`feed.слоти` лишає `місце=None` НАВМИСНО — його ставить композитор, і композитор
його не ставить (`K-ACC-12` це прямо називає розривом контракту). Отже єдине
правило теми-10, яке каталог РОЗШИРЮЄ, не спрацьовувало жодного разу.

ПІСЛЯ — дві гілки, і жодна не вигадує рішення за композитора.
  1. Коли ВСІ допустимі місця речі приобличчеві, поле займається в БУДЬ-ЯКІЙ
     гілці невирішеного вибору, і місце можна не обирати. Такі речі є: снуд,
     хомут і шарф-краватка мають замкнену конструкцію (3 із 93 шарфів, 3.2 %).
  2. Коли вибір справді щось міняє — названий рядок черги замість тиші."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, accessory as АК

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
шарфи = [c for c in кат if c.get("слот") == "шарф"]
замк = [c for c in шарфи if tuple(c.get("місця") or ()) == ("шия", "волосся")]
багато = [c for c in шарфи if len(c.get("місця") or ()) > 2]
print("шарфів у пакеті %d · замкненої конструкції %d · багатомісних %d"
      % (len(шарфи), len(замк), len(багато)))
база = [next(c for c in кат if c.get("слот") == сл) for сл in ("низ", "взуття", "сумка")]

# ── гілка 1: носій є попри необране місце ───────────────────────────────────
о = ((json.loads(B.виклик("від_моделі", json.dumps(
    dict(вх, ід=[c["id"] for c in база] + [замк[0]["id"]]), ensure_ascii=False))
    ).get("вердикт") or {}).get("образи") or [{}])[0]
р = next((z for z in (о.get("знахідки") or []) if z.get("правило") == "K-ACC-07"), None)
print("замкнений «%s» місця=%s" % (замк[0]["назва"][:36], замк[0].get("місця")))
print("   K-ACC-07 у вердикті:", "НЕМА" if not р else
      "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:58]))
assert р, "коли всі місця приобличчеві, носій є в будь-якій гілці вибору"

# ── гілка 2: вибір щось міняє → названий рядок черги, не тиша ───────────────
речі = [dict(c) for c in база] + [dict(багато[0])]
для_гілки = АК.перевірити(None, речі)
ч = next((z for z in (для_гілки.get("без_відповіді") or [])
          if z.get("правило") == "K-ACC-07"), None)
print("багатомісна «%s» місць %d" % (багато[0]["назва"][:36], len(багато[0].get("місця") or ())))
print("   K-ACC-07 у черзі:", "НЕМА" if not ч else "%s · %s" % (ч["сила"], ч["суть"][:58]))
assert ч, "необране місце мусить бути названим блокером, а не тишею"
