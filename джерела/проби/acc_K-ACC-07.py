"""K-ACC-07: каталог сам не підтверджує місце шарфа; поле займає лише відомий носій."""
import sys
from pathlib import Path
ТУТ = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ТУТ))
import feed as Ф, фід_каталог as К, accessory as А

def головна():
    """Зіставляє каталог без місця зі словом стилістки на тих самих шарфах."""
    кат = К.прочитати_каталог(Ф.каталог_на_диску(), 0)["каталог"]
    шарфи = [c for c in кат if c.get("слот") == "шарф"]
    assert шарфи, "у каталозі мають бути шарфи для перевірки"
    без_місця = [р for р in шарфи if not р.get("місце_речі") and not р.get("місце_стилістки") and р.get("near") is None]
    носії = [р for р in без_місця if А.носій_приобличчевого_поля([р]) is not None]
    print("шарфів", len(шарфи), "без місця", len(без_місця), "носіїв без джерела", len(носії))
    assert not носії, "допустимі місця каталогу не є фактом, як шарф вдягнено"
    for слово, очікувано in (("так", True), ("ні", False)):
        р = dict(без_місця[0], місце_стилістки=dict(біля_обличчя=слово, слова="як шарф вдягнено в образі"))
        з = А.перевірити(None, [р])
        факт = з.get("носій_приобличчевого_поля") is not None
        print("слово стилістки", слово, "→ носій", факт)
        assert факт == очікувано

if __name__ == "__main__":
    головна()
