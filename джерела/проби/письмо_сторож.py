"""ОЦІНКА-МОВА (рядки 1432, 1433): сторож письма показу (`латинськіЗалишкиП`) на словах розбору 02.10 —
биті знаки, літери не з української абетки, латинка в українському слові ловляться; законне (бренд у `свої`,
«V-подібний», «den», SPF) — ні. Друкує, що знайдено в кожному прикладі. Запуск: python3 проби/письмо_сторож.py"""
import os, re, subprocess, json
ДЖ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
т = open(os.path.join(ДЖ, "показ.html"), encoding="utf-8").read()
поч = т.index("const ЗАКОННА_ЛАТИНКА_П"); кін = т.index("/* ТЕКСТ ЧАТУ ПРОХОДИТЬ ТОЙ САМИЙ СТОРОЖ")
словаП = re.search(r"function словаП\(т\)\{.*?\}\n", т).group(0)
ПРИКЛАДИ = [("тонка полі† пряжка", []), ("мохо��ий кардиган", []), ("з пэчворковим принтом", []),
            ("який макіяж planуєш", []), ("тобі personally личить", []), ("spідниця кльош", []),
            ("V-подібний виріз, колготи 40 den, крем SPF", []), ("Сумка Сromia PERLA", ["сromia", "perla"]),
            ("Блуза плісе cірий", []), ("Сукня бежева, вільна", [])]
код = словаП + т[поч:кін] + "const П=%s;for(const [т,с] of П) console.log(JSON.stringify([т, латинськіЗалишкиП(т, new Set(с))]));" \
    % json.dumps(ПРИКЛАДИ, ensure_ascii=False)
вих = subprocess.run(["node", "-e", код], capture_output=True, text=True)
if вих.returncode:
    raise SystemExit("node: " + вих.stderr[-400:])
спіймано = 0
for р in вих.stdout.splitlines():
    текст, знайдено = json.loads(р)
    спіймано += bool(знайдено)
    print("%-45s → %s" % (текст, знайдено or "чисто"))
print("прикладів зі знахідкою: %d з %d (очікувано 7; законні — «V-подібний / den / SPF», бренд у своїх, "
      "українське речення)" % (спіймано, len(ПРИКЛАДИ)))
