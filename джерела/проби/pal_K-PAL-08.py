# -*- coding: utf-8 -*-
"""K-PAL-08 (контраст як носій) — умова прийому судить образ.

Корпус (тема-2:1854): «колір ПОЗА палітрою можна нести, якщо контраст образу
збігається з контрастом людини» (Lamport: «easier to wear less flattering colours
if you're wearing the right contrast levels», hint). Прийом стояв у `ПРИЙОМИ`,
лишав слід «активний» — і жодного образу не судив, хоч говорить він рівно про
образ: чи Є в ньому носій для чужого кольору.
ПІСЛЯ: правило говорить тільки тоді, коли колір поза палітрою в образі Є (інакше
йому нема про що судити), і міряє розмах світлоти образу тими самими смугами
K-PAL-15, якими код уже породжує трійки (низький ≤ 45 L*, високий ≥ 30).
Запуск із теки `джерела`: `python3 проби/pal_K-PAL-08.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import pipeline as PL

вх, r, кат, спец = ПВ.стенд(гілка=0, намір="statement")
П = спец["палітра_практична"]
чужий = lambda L, C, h, _: (not PL._нейтральний_тон(h, C, L)
                            and not PL._у_вікнах(П["вікна"], L, C, h))
# СВІТЛА річ поза палітрою: щоб пара з темним низом дала розмах понад 45 L*,
# один із двох мусить стояти на краю шкали. Беремо з каталогу, якщо пул не дав.
світлий_чужий = lambda L, C, h, з: чужий(L, C, h, з) and L >= 70
поза = (next((x for с in ("верх", "сукня") for x in [ПВ.взяти(r, кат, с, світлий_чужий)] if x), None)
        or ПВ.з_каталогу(кат, "верх", світлий_чужий)
        or next((x for с in ("верх", "сукня") for x in [ПВ.взяти(r, кат, с, чужий)] if x), None))
if not поза:
    print("ФАКТ · у пулі нема речі поза палітрою — носія нема для чого шукати"); raise SystemExit(0)
L_поза = ПВ.lch(кат, поза["id"])[0]
print("колір поза палітрою: %s L%.0f C%.0f h%.0f"
      % ((поза["назва"] or "")[:34], *ПВ.lch(кат, поза["id"])))

# ДВА ОБРАЗИ З ТІЄЮ САМОЮ ЧУЖОЮ РІЧЧЮ: в одному носій (збіг контрастів) є, в
# другому нема. Компаньйони добираються ПІД КОЖЕН випадок — інакше взуття з
# власним L* тягне розмах і обидва образи виходять однакові.
def образ(смуга):
    решта = []
    for с in ("низ", "взуття", "сумка"):
        x = (ПВ.взяти(r, кат, с, lambda L, C, h, _: смуга(L))
             or ПВ.з_каталогу(кат, с, lambda L, C, h, _: смуга(L)))
        if x: решта.append(x)
    return решта

for мітка, смуга in (("носія нема (розмах > 45)", lambda L: abs(L - L_поза) > 45),
                     ("носій є (розмах ≤ 45)", lambda L: abs(L - L_поза) <= 20)):
    решта = образ(смуга)
    if len(решта) < 2:
        print("%-26s образу з такою смугою не скласти" % мітка); continue
    ід = [x["id"] for x in [поза] + решта]
    Ls = [ПВ.lch(кат, i)[0] for i in ід]
    зн, _ = ПВ.знахідки(вх, ід)
    z = next((x for x in зн if x.get("правило") == "K-PAL-08"), None)
    print("%-26s L*%.0f…%.0f, розмах %.0f · K-PAL-08: %s"
          % (мітка, min(Ls), max(Ls), max(Ls) - min(Ls), ПВ.рядок(зн, "K-PAL-08")))
    assert bool(z) == (max(Ls) - min(Ls) > 45), (мітка, bool(z), max(Ls) - min(Ls))
print("ФАКТ · правило говорить рівно там, де носія нема, і мовчить там, де він є")
