"""ВІДПОВІДЬ СТИЛІСТКИ НЕ ГУБИТЬСЯ МОВЧКИ (рядок 209, звіт ноутбука 25.09, жива gemma-4-12b).
Модель повернула ключ «відповідь_людини» замість «відповідь_людині»: JSON валідний, розбір читав
тільки точне ім'я — і в чаті «Ір, собаки» лишився сам рядок коду про джинси, без слова стилістки.
Відповідь тут — ДОСЛІВНА з того прогону. СЛОВНИКА ОДРУКІВОК НЕМА: код бере чужий ключ тоді й лише
тоді, коли текст у відповіді один; інакше просить показ перепитати ОДИН раз. Обидва шляхи — у звіт."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import паспорт_нагоди as ПН
ВІДП = ("Вітер несе, тому до світлих джинсів кльош візьми куртку-вітрівку без підборів "
        "та шкарпетки, а для ніжності — м'яку кофту")
СЦ = dict(нагода="щоденне", місце="парк", година=11, темп_c=18.0, типові_поля=["година", "темп_c"])
СЛОВА = "гуляю з собаками в парку, вітер, яскраво хочу одягатись, у мене є світлі джинси кльош"
БАЗА = dict(подія="прогулянка з собаками", нагода="щоденне", місце="парк", формат="просто неба")
ВИПАДКИ = [   # (як звати ключ відповіді в JSON моделі, ще один чужий текст, чи чекаємо відповідь)
    ("відповідь_людині", None, True),        # схема дотримана — як було, так і лишається
    ("відповідь_людини", None, True),        # одруківка живої моделі: єдиний чужий текст = відповідь
    ("reply", None, True),                   # будь-яке інше чуже ім'я проходить тим самим шляхом
    ("відповідь_людини", "коментар", False),  # два чужі тексти — код не вгадує, показ перепитає
    (None, None, False)]                     # відповіді нема зовсім — те саме, один повтор
згублено, повторів, рядків = 0, 0, 0
for ключ, ще, чекаємо in ВИПАДКИ:
    об = dict(БАЗА)
    if ключ:
        об[ключ] = ВІДП
    if ще:
        об[ще] = "Ще один текст, який теж міг би бути відповіддю."
    п = ПН.паспорт_з_json(json.dumps(об, ensure_ascii=False), СЦ, СЛОВА)
    є = bool(str(п["відповідь_людині"]).strip())
    звіт = [x for x in (п.get("не_взято_кодом") or []) if "відповід" in x]
    рядків += len(звіт)
    повторів += 1 if п.get("потрібен_повтор") else 0
    згублено += 1 if (not є and not п.get("потрібен_повтор")) else 0
    print("   ключ %-18s → відповідь %s · повтор %s\n      звіт: %s"
          % (ключ or "нема", ("«%s…»" % п["відповідь_людині"][:34]) if є else "НЕМА",
             "так" if п.get("потрібен_повтор") else "ні", (звіт[0][:96] if звіт else "—")))
    assert є == чекаємо, (ключ, ще, п["відповідь_людині"])
print("випадків %d · відповідь загубилась мовчки: ДО %d → ПІСЛЯ %d · показ перепитає раз: %d · рядків у звіт власника: %d"
      % (len(ВИПАДКИ), sum(1 for к, _, _ in ВИПАДКИ if к != "відповідь_людині"), згублено, повторів, рядків))
assert згублено == 0, "відповідь стилістки зникла й ніхто про це не сказав"
