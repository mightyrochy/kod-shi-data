import json, bridge as B
дж = lambda x: json.dumps(x, ensure_ascii=False)
вх0 = json.load(open("стенд_вх.json", encoding="utf-8"))
СЦЕНИ = {
 "весілля гостею, 7 год": dict(подія="весілля подруги", нагода="весілля_гість", місце="ресторан_районний",
     формат="змішано", тривалість_год=7, рух="танці", ошатність=[7, 9], година=17, темп_c=20, опади="ні"),
 "офіс, 9 год": dict(подія="робочий день", нагода="робота", місце="офіс", формат="приміщення",
     тривалість_год=9, дрес_код="business_casual", година=9, темп_c=18, опади="ні"),
 "прогулянка бруківкою, 3 год": dict(подія="прогулянка старим містом", нагода="прогулянка", місце="старе місто",
     формат="просто неба", рух="багато ходити", тривалість_год=3, година=15, темп_c=18, опади="ні")}
for назва, п in СЦЕНИ.items():
    вх = dict(вх0, сценарій=dict(вх0["сценарій"], нагода=п["нагода"], місце=п["місце"], дрес_код=п.get("дрес_код")),
              паспорт=dict(п, вето={"типи": [], "тканини": [], "принти": [], "кольори": [], "зони": []}), сід=4)
    к = json.loads(B.виклик("запити", дж(вх)))["кандидати"]
    кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
    вз = [c for c in кат.values() if c.get("слот") == "взуття"]
    if назва.startswith("весілля"):
        print("пар у каталозі %d, з висотою %d (%.0f %%)" % (len(вз), sum(c.get("каблук_см") is not None for c in вз),
              100.0 * sum(c.get("каблук_см") is not None for c in вз) / len(вз)))
    каблук = next((x["id"] for x in к["взуття"] if (кат[x["id"]].get("каблук_см") or 0) >= 6), "ж-10287@giardini-shoes.com")
    основа = [к["сукня"][0]["id"]] if назва.startswith("весілля") else [к["верх"][0]["id"], к["низ"][0]["id"]]
    r = json.loads(B.виклик("від_моделі", дж(dict(вх, ід=основа + [каблук, к["сумка"][0]["id"]]))))
    н = r.get("носіння_жінці") or {}; д = н.get("пара_добір") or {}; пара = н.get("пара") or {}
    print("\n%s · образ із «%s» (%s см)\n  рядок: %s" % (назва, кат[каблук]["назва"][:40], кат[каблук].get("каблук_см"), н.get("рядок") or "—"))
    print("  низьких %s (з висотою %s, пласких за типом %s) → кандидатів %s (з пулу %s, з каталогу %s)"
          % (д.get("низьких"), д.get("з_висотою"), д.get("пласких_за_типом"), д.get("кандидатів"), д.get("з_пулу"), д.get("з_каталогу")))
    print("  знято: %s" % "; ".join("%s %d" % кв for кв in sorted((д.get("знято") or {}).items(), key=lambda кв: -кв[1])))
    print("  пара: %s" % ("«%s» %s · %s · вікно %s · %s" % (пара["назва"], пара["id"], пара["за_чим"], пара["вікно"], пара["звідки"])
                         if пара else "нема — %s" % д.get("чому_нема")))
