# -*- coding: utf-8 -*-
"""Стежені правила не міняють вихід `бриф`/`простір`/`_пакет` на записаному прогоні; зламані — міняють (крок 1.1-Б).

Факт: кожен різний виклик цих функцій на 124 записаних входах повторено без стежених і зі стеженими, як записано: вихід і
тінь однакові, побудова за стеженими не питала (`поломки.ПИТАЛИ_СТЕЖЕНІ`) — вони поза ключем кешу. Те саме без зламаних:
вихід інший — зламані лишаються в ключі. Каталог треба розпакувати з тієї самої сторінки, на якій записано входи.
Прогін: cd джерела && python3 проби/кеш_входу_11б.py --каталог /шлях/каталог_brief.xml [--входи запис.jsonl.gz]
Помилка відтворення, брак контрольних станів чи розбіжність завершують пробу кодом 1.
"""
import sys, os, asyncio, functools, collections, argparse, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); sys.path.insert(0, os.path.join(sys.path[0], 'прилади'))
import кеш_входу as КВ
ЖУРНАЛ, Ч, побачено = [], collections.Counter(), set()
стара = КВ.за_входом
def нова(ємність):
    def д(ф):
        о = стара(ємність)(ф)
        @functools.wraps(ф)
        def w(*а, **к):
            до = ПР2.ПИТАЛИ_СТЕЖЕНІ[0]
            ЖУРНАЛ.append((ф, а, к, ПР2.зламані(), ПР2.стан_стежених())); р = о(*а, **к)
            Ч[ф.__name__, 'питали'] += ПР2.ПИТАЛИ_СТЕЖЕНІ[0] != до
            return р
        w.__wrapped__ = ф; w.лічильник = о.лічильник; w.скинути = о.скинути
        return w
    return д
# Журнал ставиться ДО імпорту `поломки`: той сам тягне `brief` і `hypergraph`, і їхні `@за_входом` застосовуються при
# імпорті — після нього підміна не бачила жодної побудови `бриф`/`простір` (рядок 9045; на `main` так само).
КВ.за_входом = нова
import поломки as ПР2, знімок_мосту as ЗМ


async def відтворити(текст, каталог):
    """Програти запис із явним каталогом і зупинитися на першій помилці моста."""
    for н, рядок in enumerate(текст.splitlines(), 1):
        if not рядок.strip(): continue
        запис = json.loads(рядок)
        вхід = json.loads(запис['вхід'])
        if 'каталог' in вхід:
            вхід['каталог'] = каталог
        запис['вхід'] = json.dumps(вхід, ensure_ascii=False)
        знімок, _ = await ЗМ.прогнати(json.dumps(запис, ensure_ascii=False))
        for результат in map(json.loads, знімок.splitlines()[1:]):
            вихід = результат.get('результат')
            помилка = результат.get('помилка') or (вихід.get('помилка') if isinstance(вихід, dict) else None)
            if помилка:
                raise RuntimeError('запис %d (%s): %s' % (н, запис['ім'], помилка))


def звірити():
    """Зіставити кожну різну побудову та відхилити порожнє покриття контрольних станів."""
    for ф, а, к, зл, ст in list(ЖУРНАЛ):   # повтори нижче теж пишуть у журнал — рахуються лише записані
        ключ = (ф.__name__, repr((а, к, sorted(зл), sorted(ст))))
        if ключ in побачено: continue
        побачено.add(ключ)
        def пуск(стежити, зламані=True):
            """Повторити пряму побудову в одному з контрольних станів руки 2."""
            КВ.скинути()
            with ПР2.прогін(set(зл) if зламані else set(), стежити=стежити):
                return ф(*а, **к), ПР2.тінь(), ПР2.зламані()
        зі, н = пуск(ст), ф.__name__
        Ч[н, 'різних'] += 1; Ч[н, 'зі стеженими'] += bool(ст); Ч[н, 'інший без стежених'] += зі != пуск(())
        # Стеження за ВСІМА кодами — на кожній побудові, а не лише записаній під стеженням: `пакет` на записі під ним
        # не будується ніколи, і без цього твердження про нього нічого не міряло (рядок 9045).
        до = ПР2.ПИТАЛИ_СТЕЖЕНІ[0]; Ч[н, 'інший під усіма стеженими'] += зі != пуск(set(ПР2.УСІ_КОДИ) - set(зл))
        Ч[н, 'питали'] += ПР2.ПИТАЛИ_СТЕЖЕНІ[0] != до
        Ч[н, 'під зламаними'] += bool(зл); Ч[н, 'інший без зламаних'] += bool(зл) and зі != пуск(ст, False)
    for н in ('бриф', 'простір', 'пакет'):
        print(н + ': ' + ' · '.join('%s %d' % (п, Ч[н, п]) for п in ('різних', 'зі стеженими', 'інший без стежених', 'питали',
                                                                   'інший під усіма стеженими', 'під зламаними', 'інший без зламаних')))
        if not all(Ч[н, п] for п in ('різних', 'під зламаними')):
            raise RuntimeError('%s: бракує побудов чи побудов під зламаними правилами' % н)
        if Ч[н, 'інший без стежених'] or Ч[н, 'інший під усіма стеженими'] or Ч[н, 'питали']:
            raise RuntimeError('%s: побудова залежить від стежених правил' % н)
        if Ч[н, 'інший без зламаних'] != Ч[н, 'під зламаними']:
            raise RuntimeError('%s: зламані правила не змінили вихід' % н)


def main():
    """Прийняти каталог, відтворити входи й перевірити твердження проби."""
    парсер = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    парсер.add_argument('--каталог', required=True, help='розпакований каталог зі сторінки записаного прогону')
    парсер.add_argument('--входи', default=ЗМ.ВХОДИ_ТИПОВІ, help='записані входи мосту, JSONL або .gz')
    арг = парсер.parse_args()
    try:
        каталог = os.path.abspath(арг.каталог)
        with open(каталог, 'rb') as файл:
            if not файл.read(1):
                raise RuntimeError('каталог порожній: %s' % каталог)
        asyncio.run(відтворити(ЗМ.прочитати(арг.входи), каталог))
        звірити()
    except (OSError, ValueError, RuntimeError, KeyError, TypeError) as помилка:
        print('ПОМИЛКА: %s' % помилка, file=sys.stderr)
        return 1
    finally:
        КВ.за_входом = стара
    return 0


if __name__ == '__main__':
    sys.exit(main())
