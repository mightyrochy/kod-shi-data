"""Назва речі на картці ріжеться посеред слова — і рівно вона їде жінці.

`-webkit-line-clamp:2` ріже назву без жодного відома коду: на знімку власника
1_kartka_kardygan_chobotu.jpg «Джемпер жіночий щільний з рукавом 3/4 демісезонний»
(50 знаків) читається як «…з рукавом 3/4…», а «Чоботи шкіряні LISS на підборах
кітен хіл» (41) влазить — звідси стеля два рядки × 20 знаків. Друкує правило з
показу й міряє, скільки справжніх назв власника за неї виходить.
"""
import json
import pathlib

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
ПОКАЗ = (КОРІНЬ / "джерела" / "показ.html").read_text(encoding="utf-8")
СТЕЛЯ = 2 * 20

for н, р in enumerate(ПОКАЗ.splitlines(), 1):
    if "line-clamp" in р:
        print("показ.html:%d" % н, р.strip()[:120])
print("місць, де назва речі ріжеться по два рядки:", ПОКАЗ.count("-webkit-line-clamp:2"),
      "· жодного рядка коду про обрізання:", ПОКАЗ.count("назва_обрізана"))

назви = {}
for ф in sorted((КОРІНЬ / "аудит" / "тести" / "власник_2026-09-25").glob("verdykty-*.json")):
    д = json.loads(ф.read_text(encoding="utf-8"))
    for п in д["прогони"]:
        for в in п["вердикти"]:
            for р in в.get("речі_образу") or []:
                н = str(р.get("назва") or "")
                if н:
                    назви.setdefault(н, (п["спільне"].get("розклад"), в.get("рука")))
довгі = {н: д for н, д in назви.items() if len(н) > СТЕЛЯ}
for н, (розклад, рука) in sorted(довгі.items()):
    print("   розклад %s · рука %s · %d знаків → «%s…» (зникає «%s»)"
          % (розклад, рука, len(н), н[:СТЕЛЯ - 3], н[СТЕЛЯ - 3:]))
print("різних назв речей у файлах власника:", len(назви), "· ріжеться:", len(довгі),
      "(%.0f %%)" % (100 * len(довгі) / max(1, len(назви))))
