"""Ф-143 — три форми запису, яких сканер контрактів не бачив, і доказ, що він не осліп.

ДО ПРАВКИ: «РОЗРИВІВ: 3» на чистому main — `task`, `твій_образ`, `є_також_у`. Усі три
ПИШУТЬСЯ, але рядок-ключ і місце, де він стає ключем, розведені: змінною петлі
(`пакет_моделі:738`), сталою (`протокол:1281`), таблицею `КЛЮЧІ_EN` (`збирач_промптів:100`).
ПІСЛЯ: форми розв'язує AST. Проба тримає ТРИ боки — форма ловиться; дзеркало, де результат
ключем НЕ стає, мовчить; поле без писаря лишається сиротою (інакше це був би глушник)."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import audit_contracts as АК

# (форма, ключ, джерело-де-ключ-СТАЄ-ключем, дзеркало-де-НЕ-стає)
ФОРМИ = [
    ("1 змінна петлі", "поле_петлі",
     'def f(r):\n    річ = {}\n    for к, зн in (("поле_петлі", 1),):\n        річ[к] = зн\n    return річ\n',
     'def f():\n    for к, зн in (("поле_петлі", 1),):\n        print(к)\n'),
    ("2 стала модуля", "поле_сталої",
     'СТАЛА = "поле_сталої"\ndef f(v):\n    return dict({СТАЛА: v})\n',
     'СТАЛА = "поле_сталої"\ndef f():\n    return [СТАЛА]\n'),
    ("3 перейменування", "поле_таблиці",
     'Т = {"к": "поле_таблиці"}\nпер = lambda с: Т.get(с, с)\n'
     'def f(v):\n    d = {}\n    d[пер("к")] = v\n    return d\n',
     'Т = {"к": "поле_таблиці"}\ndef f(м):\n    return Т.get(м, м)\n'),
]

print("ФОРМА                 ключ            ЛОВИТЬСЯ  дзеркало-НЕ-ключ")
впало = 0
for назва, ключ, джерело, дзеркало in ФОРМИ:
    є = ключ in АК._розведені_ключі(джерело)[0]
    хибно = ключ in АК._розведені_ключі(дзеркало)[0]
    впало += (not є) + хибно
    print("%-21s %-15s %-9s %s" % (назва, ключ, "так" if є else "НІ ✗",
                                   "хибно ✗" if хибно else "мовчить"))
# НЕ ОСЛІП: поле, яке читають і ніде не пишуть, жодна з форм за запис не візьме.
осліп = "сирота_проби" in АК._розведені_ключі('def f(d):\n    return d.get("сирота_проби")\n')[0]
впало += осліп
print("сирота (читають, не пише ніхто): %s" % ("ВЗЯТО ЗА ЗАПИС ✗" if осліп else "лишається сиротою"))
print("ВПАЛО %d" % впало)
sys.exit(1 if впало else 0)
