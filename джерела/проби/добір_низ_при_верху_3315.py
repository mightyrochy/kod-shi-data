"""Рядок 3315: образ має верх (+ жакет, взуття, сумку), низу нема, у пулі перша — сукня.
До правки `_дібрати_кодом` брав сукню (слоти `сукня → комплект → верх → низ`), після — низ.
Запуск із теки `джерела`: `python3 проби/добір_низ_при_верху_3315.py`."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import повнота_образу as ПО
сл = {"корсет": "верх", "жакет": "верхній_шар", "туфлі": "взуття", "шопер": "сумка"}
р = lambda н, с: {"id": н, "слот": с}
пул = {"сукня": [р("сукня1", "сукня")], "низ": [р("штани1", "низ")], "верх": [], "взуття": [], "сумка": []}
сл_ = {**{н: р(н, с) for н, с in сл.items()}, "сукня1": р("сукня1", "сукня"), "штани1": р("штани1", "низ")}
for назва, пул_ in (("сукня і низ у пулі", пул), ("лише сукня у пулі", {**пул, "низ": []})):
    ід, дібр, ні = ПО._дібрати_кодом(list(сл), None, пул_, dict(сл_), {"нагода": "весілля"})
    print("%-20s → дібрано %s · чому_ні %s" % (назва, [(d["id"], d["слот"]) for d in дібр], ні))
