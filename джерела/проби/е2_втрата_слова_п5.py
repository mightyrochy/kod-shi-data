"""Корінь Е2-втрата-слова, п.5: читач бере те значення, що й рішення поруч. Злива (сильна непогода) з її проханням
замші й без нього, каталог_повний, рука 1 через міст `запити`: рядок брифа K-WEA-01 (заява) проти пулу (замша/нубук/
велюр у взутті). ДО бриф судив непогоду парою (сцена, сцена) — прохання замші є лише в паспорті; ПІСЛЯ — (сцена,
паспорт), як пул. Ще — мета всього образу «приховати» + зона (`регістр_уваги.мета_образу`) і невживані параметри
(`канон_опади`, `блокер_пальта`). Моделі не кличе. Запуск: cd джерела && python3 проби/е2_втрата_слова_п5.py"""
import inspect, json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed as Ф; Ф.каталог_на_диску("каталог_повний.xml")
import bridge as B, brief as Б, міст_пакет as МП, аксесуари_погода as АП, регістр_уваги as РУ, сценарій as С, суд_погода as СП
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
б_усі, _бриф = [], Б.бриф
Б.бриф = lambda *a, **k: б_усі.append(_бриф(*a, **k)) or б_усі[-1]   # бриф, який міст справді збирає
for підпис, бж in (("злива, без прохання", None), ("злива, вона просить замшу", "замша")):
    сц = {k: v for k, v in вх["сценарій"].items() if k not in ("темп_c", "погода_відчуття")}
    d = dict(вх, сценарій=dict(сц, нагода="щоденне", місце="місто", дрес_код=None, опади="злива", смуга_погоди="mild"))
    if бж:
        d["паспорт"] = dict(бажання=["замшеві черевики"], бажання_коди=[dict(слот="взуття", тканина=бж, фраза="замшеві черевики")])
    МП.КЕШ_ПАКЕТА.clear(); б_усі.clear()
    r = json.loads(B.виклик("запити", json.dumps(d, ensure_ascii=False)))
    кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
    вз = r["кандидати"].get("взуття", [])
    замша = sum(1 for c in вз if АП.відмовляє_у_волозі(кат.get(c["id"]) or c))
    рядки = [з.get("code") for p in б_усі[0]["правила"] if p["код"] == "K-WEA-01"
             for з in (p.get("заява") or [])]
    print("%-26s пул: взуття %d, замша/нубук/велюр %d · бриф K-WEA-01: %s" % (підпис, len(вз), замша, рядки or "нема"))
print("мета_образу параметри:", list(inspect.signature(РУ.мета_образу).parameters),
      "· «приховати»:", РУ.мета_образу("приховати"))
print("канон_опади параметри:", list(inspect.signature(С.канон_опади).parameters),
      "· блокер_пальта параметри:", list(inspect.signature(СП.блокер_пальта).parameters))
