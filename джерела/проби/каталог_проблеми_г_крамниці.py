# -*- coding: utf-8 -*-
"""Рядки 5622/5623 (реєстр 5616, клас Г3/Г4): перелік крамниць жниварки (`zhnyvarka/магазини.tsv`) проти каталогу.
Факт: увімкнені крамниці без жодної речі, вимкнені крамниці, чиї речі досі в каталозі (з причиною вимкнення),
крамниці каталогу поза переліком і частка п'яти найбільших. Запуск: python3 джерела/проби/каталог_проблеми_г_крамниці.py"""
import collections, gzip, os, re                                               # noqa: E401
К = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
xml = gzip.open(os.path.join(К, "каталог_повний.xml.gz"), "rt", encoding="utf-8").read()
у_каталозі = collections.Counter(re.findall(r'<param name="магазин">([^<]*)<', xml))
рядки = [р.rstrip("\n").split("\t") for р in open(os.path.join(К, "zhnyvarka", "магазини.tsv"), encoding="utf-8")
         if not р.startswith("#")][1:]
перелік = {р[0].replace("www.", ""): (р[4], р[7] if len(р) > 7 else "") for р in рядки}
print("у переліку %d (увімкнено %d, вимкнено %d) · у каталозі крамниць %d, речей %d" % (len(перелік),
      sum(1 for с, _ in перелік.values() if с == "увімкнено"), sum(1 for с, _ in перелік.values() if с == "вимкнено"),
      len(у_каталозі), sum(у_каталозі.values())))
нулі = sorted(д for д, (с, _) in перелік.items() if с == "увімкнено" and not у_каталозі.get(д))
print("увімкнено, 0 речей у каталозі: %d · %s" % (len(нулі), ", ".join(нулі)))
мало = sorted((у_каталозі[д], д) for д, (с, _) in перелік.items() if с == "увімкнено" and 0 < у_каталозі.get(д, 0) < 50)
print("увімкнено, менше 50 речей: %d · %s" % (len(мало), ", ".join("%s %d" % (д, ч) for ч, д in мало)))
вимк = [(д, у_каталозі[д], н) for д, (с, н) in перелік.items() if с == "вимкнено" and у_каталозі.get(д)]
print("вимкнено, але речі в каталозі: %d крамниць, %d речей" % (len(вимк), sum(ч for _, ч, _ in вимк)))
for д, ч, н in вимк:
    print("  %-22s %5d · %s" % (д, ч, н[:90]))
поза = [д for д in у_каталозі if д not in перелік]
print("у каталозі, поза переліком: %s" % ", ".join("%s %d" % (д, у_каталозі[д]) for д in поза))
топ = у_каталозі.most_common(5)
print("п'ять найбільших — %.0f %% каталогу: %s" % (100 * sum(ч for _, ч in топ) / sum(у_каталозі.values()), топ))
