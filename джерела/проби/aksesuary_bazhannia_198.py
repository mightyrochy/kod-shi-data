import json, os, sys
Д = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, Д); os.chdir(Д)
import feed; feed.каталог_на_диску()
import bridge as B, різноманітність_пулу as R
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
ЇЇ = "хочеться більше ремінців, шарфів чи кепок"
ФОРМИ = ["шарф", "шарфи", "шарфів", "шарфик", "ремінь", "ремінців", "кепка", "кепки",
         "кепок", "шапка", "шапок", "хустка", "хусток", "поясок", "паски"]
без_слота, без_речей = [], []
for ф in ФОРМИ:
    сл, _ = R.слот_бажання(ф)
    осн = [о for о, ні in R._слова(ф) if not ні]
    n = sum(1 for r in кат if r.get("слот") == сл
            and any(о in str(r.get("назва") or "").lower() for о in осн)) if сл else 0
    (без_слота if not сл else без_речей if not n else []).append(ф)
    print("   «%-9s» → слот %-14s основа %-8s речей слота з основою в назві: %d"
          % (ф, сл, "/".join(осн), n))
з = R.речі_бажання(ЇЇ, кат, {с: [] for с in ("шарф", "пояс", "головний_убір")}, сід=3, n=4)
слоти_речей = sorted({r.get("слот") for r in (з or {}).get("речі") or []})
рядок = R.рядок_вимоги([(ЇЇ, з)]) or ""
названі = sorted(с for с in ("шарф", "пояс", "головний_убір") if "«%s»" % с in рядок)
print("ФАКТ · форм %d · без слота %s · зі слотом, але без речей %s"
      % (len(ФОРМИ), без_слота or "нема", без_речей or "нема"))
print("ФАКТ · «%s» → слоти фрази %s, речі лягли у %s, рядок моделі називає %s"
      % (ЇЇ, (з or {}).get("слоти"), слоти_речей, названі))
assert not без_слота and not без_речей, "її слово в цій формі до пулу не доходить"
assert названі == слоти_речей, "рядок обіцяє моделі слот, у якому підбір речі не дав"
