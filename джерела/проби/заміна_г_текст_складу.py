"""Е3-заміна-з-перевіркою, умова «г»: рішення коду про заміну з фото на мосту (стенд_вх.json, сід 3) і рядок картки
про вирішений склад (`заміна_з_фото.текст_складу`) для кожного рішення; опис вирішеного складу не просить `swap`;
опис поля підстави називає коди переліку. Друкує факт. Запуск: cd джерела && python3 проби/заміна_г_текст_складу.py"""
import sys, os, json, re, tempfile
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge as B, feed as F, розбір_відповідей as Р, протокол as П
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), каталог=F.каталог_на_диску("каталог_brief.xml"), сід=3)
вх["кеш_кольорів"] = os.path.join(tempfile.gettempdir(), "кеш_живого_шляху.json")
if not os.path.exists(вх["кеш_кольорів"]): json.dump({}, open(вх["кеш_кольорів"], "w"))
міст = lambda ім, d: json.loads(B.виклик(ім, json.dumps(d, ensure_ascii=False)))
пул = міст("запити", вх)["пакети"]["1"]["пул"]
образи = [dict(ід="о%d" % (і + 1), підпис="t", речі=[пул[с][і]["н"] for с in ("верх", "низ", "взуття", "сумка", "шарф", "верхній_шар")]) for і in (0, 1)]
в1 = міст("від_моделі", dict(вх, текст_моделі=json.dumps(dict(версія="1", образи=образи), ensure_ascii=False)))
вб = міст("від_моделі", dict(вх, ітерація=2, відповідь="ВИБІР_V1", вибір_над=в1["вибір_над"], текст_моделі=json.dumps(dict(версія="1", обрано=в1["вибір_над"]["образи"][0]["ід"]))))["вибір"]
верх, оп = вб["ід"][0], dict(вх, ітерація=2, відповідь="ОПИС_ВІДПОВІДЬ_V1", ід=вб["ід"], інші_образи=[о["ід"] for о in в1["образи"]])
відп = lambda **з: json.dumps(dict(version="1", text="t", how_to_wear=[], wrong_photos=[], **з), ensure_ascii=False)
код = lambda з: ((з.get("текст") or {}).get("statements") or [{}])[0].get("code", "—")
def рядок(назва, з): print("%-34s стан=%-9s відмова=%-26s рядок=%s" % (назва, з.get("стан"), з.get("відмова") or "—", код(з))); return з
н = вб["номери"][верх]
for чому in ("colour", "occasion", "day", "colour: its creamy near-white shade is too close…"):
    з1 = рядок("перший опис, why=" + чому[:20], міст("від_моделі", dict(оп, текст_моделі=відп(swap=dict(item=н, why=чому))))["заміна"])
рядок("перший опис, номер не прочитано", міст("від_моделі", dict(оп, текст_моделі=відп(swap=dict(item="#999·99", why="colour"))))["заміна"])
з1 = міст("від_моделі", dict(оп, текст_моделі=відп(swap=dict(item=н, why="colour"))))["заміна"]
# сід 3 запасних не дає (no_spares) — другу відповідь показуємо над кандидатами слота з пулу, як показ після кроку 2
кс = [р for п in B._КЕШ_ПАКЕТА.values() for р in (п.get("кандидати") or {}).get("верх", []) if р["id"] != верх][:3]
з1 = dict(з1, запасні=[dict(id=р["id"], н=р.get("н") or р["id"]) for р in кс]) if not з1.get("запасні") else з1
if з1.get("запасні"):
    зп = dict(річ=з1["річ"], чому="colour", запасні=[x["id"] for x in з1["запасні"]])
    рядок("друга відповідь без swap", міст("від_моделі", dict(оп, заміна_запасні=зп, текст_моделі=відп()))["заміна"])
    рядок("друга відповідь: обрано запасну", міст("від_моделі", dict(оп, заміна_запасні=зп, текст_моделі=відп(
        swap=dict(item=н, why="colour", to=з1["запасні"][0]["н"]))))["заміна"])
о = міст("опис", dict(вх, речі=вб["ід"], номери=вб["номери"], рішення_заміни=dict(річ=верх, стан="kept", текст=з1["текст"])))
пр = json.loads(о["промпт"])
print("опис вирішеного складу: swap_decided =", пр.get("swap_decided"), "· «swap» у скелеті:", '"swap"' in json.dumps(пр["task"] if "task" in пр else пр),
      "· missing:", json.dumps(пр.get("missing"), ensure_ascii=False)[:160])
опис_поля = Р.ОПИС.поля_виходу["заміна.чому"]
print("опис поля підстави називає коди:", {к: bool(re.search("«%s»" % к, опис_поля)) for к in П.ПІДСТАВИ_ЗАМІНИ})
