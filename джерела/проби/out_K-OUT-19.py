# -*- coding: utf-8 -*-
"""K-OUT-19 (пояс тренча завʼязується, і місце вузла — функція стану).

ДО ПРАВКИ: знахідка народжувалась у `outer.команди_укладки`, лягала у відро
`команди` — і далі не йшла нікуди: `composer._оцінити` бере з гілки верхнього
шару лише `ворота` й `преференції`, а `перевірити_від_моделі` пакував команди в
діагностичний `канал_3` БЕЗ `сила_нп`. У вердикті рядка не було ніколи.
ПІСЛЯ: команди верхнього шару дописуються до знахідок ПІСЛЯ `_оцінити` (у ключ
ранжування не входять), і рядок стоїть у `вердикт.образи[0].знахідки`."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
вх["сценарій"].update(темп_c=-2, опади="ні", вітер=8, тривалість_год=2)
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
_кат = B.каталог_останнього_пакета()
кат = {c["id"]: c for c in _кат}
к = з["кандидати"]
взяти = lambda сл, ум: next((кат[r["id"]] for r in (к.get(сл) or [])
                             if r["id"] in кат and ум(кат[r["id"]])), None)
# ── ТРЕНЧ БЕРЕТЬСЯ З КАТАЛОГУ ПАКЕТА, А НЕ З ПУЛУ КАНДИДАТІВ ────────────────
# ЩО ЦЕ МІНЯЄ. Проба шукала тренч у `кандидати["верхній_шар"]` — тобто серед
# ~35 речей, які пул віддав МОДЕЛІ. Виміряно (`каталог_повний`, сценарій цієї
# проби): у каталозі пакета тренчів і плащів із оголошеним поясом 10, у пулі
# кандидатів верхнього шару — 0, і `next(...)` віддавав None, після чого проба
# падала TypeError на `тренч["назва"]`, тобто НЕ ДРУКУВАЛА СВОГО ФАКТУ взагалі.
# Це не дефект правила й не дефект пулу: пул відбирає за кольоровим вікном і
# бюджетом символів, а не за бортністю, і вимагати від нього саме тренч із
# поясом означало б міряти відбір, а не K-OUT-19. Проба міряє ДОСЯЖНІСТЬ
# правила на речі каталогу — рівно так, як це вже робить `wea_K-WEA-03.py`.
# ЧОГО ПРОБА ТЕПЕР НЕ ЗАМОВЧУЄ: скільки таких речей у пулі (нуль — теж число).
_тр_пул = [кат[r["id"]] for r in (к.get("верхній_шар") or [])
           if r["id"] in кат and кат[r["id"]].get("тип_верхнього") in ("тренч", "плащ")
           and кат[r["id"]].get("пояс")]
_тр_кат = [c for c in _кат if c.get("тип_верхнього") in ("тренч", "плащ") and c.get("пояс")]
print("тренчів із поясом: у каталозі пакета %d · у пулі кандидатів %d"
      % (len(_тр_кат), len(_тр_пул)))
if not _тр_кат:
    print("K-OUT-19: БЕЗ ВХОДУ — тренча чи плаща з оголошеним поясом у каталозі нема")
    raise SystemExit(0)
тренч = (_тр_пул or _тр_кат)[0]
ід = [r["id"] for r in (тренч, взяти("сукня", lambda c: True),
                        взяти("взуття", lambda c: True)) if r]
print("тренч:", тренч["назва"][:56], "· пояс", тренч.get("пояс"))
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
р = next((z for z in (о.get("знахідки") or []) if z.get("правило") == "K-OUT-19"), None)
print("канал_3 (діагностика) як був:",
      [z.get("правило") for z in ((вм.get("канал_3") or {}).get("команди") or [])] or "—")
print("K-OUT-19 у вердикті:", "НЕМА" if not р else
      "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:58]))
print("ремонт рядка:", str((р or {}).get("ремонт"))[:80])
