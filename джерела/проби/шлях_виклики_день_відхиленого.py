# -*- coding: utf-8 -*-
"""Розбір шляху 4/8 · опис після відхиленого вибору. Коли вибір «о1» код відхилив, показ бере склад картки з
`повнота` (найповніший образ вердикта ремонту), а в `містП('опис')` шле `образ: вб.обрано || …` і `день: вб.день`
(`показ.html`, виклик опису). Ремонт: п'ять образів, у кожного своє «день» з назвою образу; о1–о4 без сумки, о5 —
двоє взуття. Друкує: що каже вибір, який образ іде на картку, і які «образ.ід» та «день_образу» бачить опис.
Запуск: cd джерела && python3 проби/шлях_виклики_день_відхиленого.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), варіантів=10, ремонт_варіантів=5, бюджет_символів=120000, без_фото=1)
пул = json.loads(json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["руки"]["1"])["пул"]
н = lambda с, k: пул[с][k % len(пул[с])]["н"]
від = lambda т, **д: json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=т, **д), ensure_ascii=False)))
склад = lambda і: [н(с, і) for с in ("верх", "низ", "взуття", "пояс")] + ([н("сумка", і), н("взуття", і + 7)] if і == 4 else [])
образи = [dict(ід="о%d" % (і + 1), підпис="образ %d" % (і + 1), день="День образу о%d." % (і + 1), речі=склад(і)) for і in range(5)]
в1 = від(json.dumps(dict(версія="1", образи=образи), ensure_ascii=False))
в2 = від(json.dumps(dict(версія="1", образи=образи), ensure_ascii=False), ітерація=2, попередній_вердикт=в1["вердикт"])
в3 = від(json.dumps(dict(версія="1", обрано="о1", чому="так", прибрати=[])), ітерація=2, відповідь="ВИБІР_V1", вибір_над=в2["вибір_над"])
вб = в3.get("вибір") or {}; пв = в2.get("повнота") or {}
print("вибір: обрано %s · ід %d · замінено %s · день «%s» · %s" % (вб.get("обрано"), len(вб.get("ід") or []), вб.get("замінено"), вб.get("день"), str(вб.get("чому_відмова"))[:80]))
print("картка (повнота ремонту): образ %s · речей %d · повний %s" % (пв.get("образ"), len(пв.get("ід") or []), пв.get("повний")))
о = json.loads(B.виклик("опис", json.dumps(dict(вх, речі=пв.get("ід"), номери=вб.get("номери") or пв.get("номери"),
               образ=(вб.get("обрано") or вб.get("замінено") or пв.get("образ")), день=(вб.get("день") or "")), ensure_ascii=False)))
п = json.loads(о["промпт"])
print("промпт опису: образ.ід %s · день_образу «%s» · речей %d" % (п["образ"].get("ід"), п.get("день_образу"), len(п["образ"]["речі"])))
