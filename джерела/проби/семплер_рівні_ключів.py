"""ПУЛ-6, вади Codex на #679: (1) квота з округленням вниз лишала рідшому рівню 0 місць — `{0:100,2:1}`, 20 → `{0:20,2:0}`;
(2) штраф речі = сума різниць рангів, а мало бути «скільки ключів гірші» (крій 0/1/2 одним ключем — штраф 2 замість 1).
Друкує факт; код виходу 1, якщо хоч одна вада жива.  Запуск: python3 проби/семплер_рівні_ключів.py"""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import семплер as С
вади = 0
for розміри, квота in (({0: 100, 2: 1}, 20), ({0: 50, 1: 30, 2: 2}, 12), ({0: 400, 1: 10, 2: 3}, 3), ({0: 5, 1: 5}, 40)):
    к = С._квоти_рівнів(розміри, квота)
    нуль = [л for л in розміри if розміри[л] and not к[л] and квота >= len(розміри)]
    вади += bool(нуль or sum(к.values()) != min(квота, sum(розміри.values())))
    print("квоти %s на %d → %s%s" % (розміри, квота, к, "  ✗ рівень без місця" if нуль else ""))
речі = [{"id": "а", "_ранг_пізній": (0, 0)}, {"id": "б", "_ранг_пізній": (2, 0)}, {"id": "в", "_ранг_пізній": (2, 1)}]
рівні = {л: [r["id"] for r in v] for л, v in С._рівні_речей(речі).items()}
ждемо = {0: ["а"], 1: ["б"], 2: ["в"]}
вади += рівні != ждемо
print("рівні речей (крій 0/2 одним ключем — 1, двома — 2): %s%s" % (dict(sorted(рівні.items())), "" if рівні == ждемо else "  ✗ очікували %s" % ждемо))
sys.exit(1 if вади else 0)
