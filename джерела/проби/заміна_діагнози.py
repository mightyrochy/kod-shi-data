"""Звіряє виміри чотирьох сімей до/після зняття неперевірених порад."""
import json, subprocess, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import outfit as О, оцінка_образу as Ц


def головна():
    """Порівнює діагнози з базою наряду на незмінних входах без викликів моделей."""
    база = "cca68e2bb1ea1583fa572b92656e0cbcaef24e19"
    F, *_ = Ц.профіль(json.loads(Path("стенд_вх.json").read_text(encoding="utf-8")))
    E = О.елементи([dict(id=с, слот=с, hex=к, площа=0.33, near=0.5)
                    for с, к in zip(("верх", "низ", "взуття"), ("#8a9a7b", "#ff5a1f", "#c2ab90"))])
    пара = [dict(id=і, візерунок="горох", масштаб_відн=м, hex=к)
            for і, м, к in (("а", 0.2, "#222222"), ("б", 0.22, "#242424"))]
    def вікна(друге):
        """Дає два виміряні вікна правил на одному носії."""
        return [dict(правило=п, запит_у_каталог=dict(слот="верх", цільова_L=в))
                for п, в in (("K-CLR-02", [60, 80]), ("K-KOH-06", друге))]
    випадки = [("колір_принти", "принти", (пара, [dict(річ=р["id"]) for р in пара]), {})]
    випадки += [("coordination", "інтенсивність", (E,), {}),
                ("coordination", "координація", (E,), dict(набір_кандидатів=[0.01, 0.1, 0.3, 0.5])),
                ("coordination", "координація", (E[:1],), {})]
    випадки += [("колір_ремонти", "несумісні_ремонти", (вікна(в),), {}) for в in ([10, 30], [70, 90])]
    випадки += [("палітра_принт", "принт_придатність",
                 (dict(масштаб_відн=0.3, чіткість_краю=0.05, ґрунт=0.95),),
                 dict(F=F, масштаб_особи=0.1, рух="кривий", риси_рух="прямий",
                      зона_камуфляж="верх", слот_принту="верх"))]
    def виміри(в):
        """Лишає всі поля, крім текстів та знятих виходів неперевірених ремонтів."""
        if isinstance(в, list): return [виміри(х) for х in в]
        return {к: виміри(х) for к, х in в.items() if к not in {
            "суть", "для_стиліста", "де_ламається", "ламається", "ремонт", "ремонт_заяви", "запит", "запит_у_каталог"}} if isinstance(в, dict) else в
    for модуль, ім, арг, поля in випадки:
        старий = {"__name__": модуль}
        exec(subprocess.check_output(["git", "show", f"{база}:джерела/{модуль}.py"]).decode("utf-8"), старий)
        assert виміри(старий[ім](*арг, **поля)) == виміри(getattr(__import__(модуль), ім)(*арг, **поля)), (модуль, ім)
    print(f"Виміри, сила, учасники, пояснення й брак входу: {len(випадки)}/{len(випадки)} незмінні")

if __name__ == "__main__": головна()
