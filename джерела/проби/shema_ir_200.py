"""ЯКУ СХЕМУ ПРОДУКТ ОБИРАЄ САМ (рядок 200). У файлі вердиктів «Ір» рука 2 має поломку «гілка None
(тональна) → 2 (нейтрали+акцент)»: без вибору жінки рука 1 бере розвилка[0]. Проба: (1) стенд — value_gap,
рівень, порядок гілок з вагою; (2) свіп value_gap — з якого місця першою стає не «тональна»; (3) чи
рухають порядок її слова/намір (statement) або волосся темніше. Запуск: cd джерела && python3 проби/shema_ir_200.py"""
import json, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from міст_вхід import _збірка, _якір, _нормалізувати_вхід, _застосувати_паспорт
import міст_основи as МО, palette as P
from палітра_схеми import частки_блоків
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
def розв(зміни, намір="conventional"):
    d = _нормалізувати_вхід(_застосувати_паспорт(dict(вх, **зміни)))
    F, T, зріст, kw = _збірка(d)
    п, і, *_ = МО._пакет_гілки(d, F, T, зріст, kw, _якір(d), намір)
    return п["палітри"], і
for мітка, зм, нм in (("стенд (волосся #f1dbaa)", {}, "conventional"),
                      ("стенд, намір statement", {}, "statement"),
                      ("волосся темно-русе #6b4e37", {"волосся": ["#6b4e37"]}, "conventional"),
                      ("волосся темне #2b1d16", {"волосся": ["#2b1d16"]}, "conventional")):
    пл, і = розв(зм, нм)
    print("%-28s value_gap %5.1f · %-8s · гілка=%s → перша «%s» · %s" % (мітка, пл["value_gap"], пл["контраст_рівень"], і,
          пл["розвилка"][0]["схема"], ", ".join("%s %.2f" % (г["схема"], г["вага_нп"]) for г in пл["розвилка"][:4])))
print("\nсвіп value_gap (межі рівнів 22/45, смуга ±6):")
перша = None
for gap in range(4, 60, 2):
    ч = частки_блоків(gap); рів = max(ч, key=ч.get)
    р = P.розвилка(dict(рівень=рів, value_gap=gap))["гілки"]
    if р[0]["схема"] != перша:
        перша = р[0]["схема"]
        print("  від gap %2d: перша «%s» (н+а %.2f проти тональної %.2f) · частки %s" % (gap, перша,
              *[next(г["вага_нп"] for г in р if г["схема"] == с) for с in ("нейтрали+акцент", "тональна")], ч))
