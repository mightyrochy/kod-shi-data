"""C-1 (звіт Research «особистий стиль»): базова лінія двох осей картки з файлів вердиктів.

Друкує з вивантажених вердиктів (кнопка «Зберегти всі вердикти файлом», `ZVIT_OUT`):
таблицю «Вдягнеш?» × «саме твоє?», причини за `для_мене`, частку пар БЕЗ РОЗКЛАДУ
(ні чипа причини, ні «не ця», ні коментаря) і клас кадру речей вердикта (П11).
«Вдягну як є + просто гарний» без розкладу — те, що звіт називає небезпекою П7:
блок «Що заважає?» для цієї пари закритий, і сказати вона нічого не може.

Запуск:  python3 джерела/проби/styl_osi_verdyktiv.py <файл вердиктів> [ще файли…]
"""
import collections, json, sys

пари, причини, без_розкладу, класи, усього = collections.Counter(), collections.defaultdict(
    collections.Counter), collections.Counter(), collections.Counter(), 0
for ф in sys.argv[1:]:
    д = json.load(open(ф, encoding="utf-8"))
    for прогін in д.get("прогони", []) or [д]:
        for в in прогін.get("вердикти", []):
            верд, моє = (в.get("вердикт_людини") or "—"), (в.get("для_мене") or "—")
            чипи = [ч for ч in (в.get("причини") or "").split("+") if ч]
            розклад = bool(чипи or (в.get("замінити") or "") or (в.get("коментар") or "").strip())
            усього += 1
            пари[(верд, моє)] += 1
            причини[моє].update(чипи or ["(без причини)"])
            if not розклад:
                без_розкладу[(верд, моє)] += 1
            for р in в.get("речі_образу") or []:
                класи[р.get("клас_кадру") or "(не міряли)"] += 1

print("вердиктів: %d · файлів: %d" % (усього, len(sys.argv) - 1))
for (верд, моє), н in sorted(пари.items(), key=lambda x: -x[1]):
    print("  «%s» × «%s»: %d · без розкладу %d" % (верд, моє, н, без_розкладу[(верд, моє)]))
for моє, лік in причини.items():
    print("  причини при «%s»: %s" % (моє, ", ".join("%s %d" % (к, н) for к, н in лік.most_common())))
print("  без розкладу всього: %d з %d" % (sum(без_розкладу.values()), усього))
print("  клас кадру речей: %s" % ", ".join("%s %d" % (к, н) for к, н in класи.most_common()))
