"""Друкує факти K-KOH-07 у суді реального образу через міст."""
import json, pathlib, sys
ДЖ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ДЖ))
import bridge as М, feed as Ф


if __name__ == "__main__":
    вхід = json.loads((ДЖ / "стенд_вх.json").read_text(encoding="utf-8"))
    вхід["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
    вхід["гілка"] = 0
    json.loads(М.виклик("запити", json.dumps(вхід, ensure_ascii=False)))
    каталог = М.каталог_останнього_пакета()
    ід = [next(р["id"] for р in каталог if р.get("слот") == слот) for слот in ("сукня", "взуття")]
    for поле in ("господар", "креативне"):
        for значення in (None, True, False):
            в = dict(вхід, ід=ід, сценарій=dict(вхід["сценарій"], **{поле: значення}))
            вихід = json.loads(М.виклик("від_моделі", json.dumps(в, ensure_ascii=False)))
            образ = вихід["вердикт"]["образи"][0]
            чекліст = образ["чекліст"]["надлишок"]
            номер = 22 if поле == "господар" else 23
            брак = [п for п in чекліст.get("вимкнено", []) if п["пункт"] == номер]
            assert bool(брак) == (значення is None), (поле, значення, чекліст)
            if брак:
                assert брак[0]["бракує"][0]["fields"] == [поле]
                пройдено = чекліст["пройдено"]
            else:
                assert чекліст["пройдено"] == пройдено + 1, чекліст
            print("образ", ід, поле, значення, "→", "без входу" if брак else "пройдено", flush=True)
