"""Рядок 202 (власник 24.09): «система знає, що є проблема, і ніяк її не вирішує». Сцени «Ір» (театр +14 °C, собаки
+16 °C з вітром) і офіс × сіди 3, 5, 7, 9 × руки 1–2; образи — як заглушка стенда (10) і 10 шарованих (верх + верхній шар).
Дефект — гейт або «слот_двічі» («лиши одну»); образ із ним подається ВПЕРТО (вердикт з нього одного; неповний — заглушка
двічі вертає його ж, далі добір кодом). ДО — `повнота_набору` без судді (як main), ПІСЛЯ — `повнота` мосту (ярус 4)."""
import json, sys, os, collections
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, pipeline as PL
СЦЕНИ = {"театр·концерт·14°C": dict(нагода="театр", місце="театр", година=19, темп_c=14, формат="змішано", рух="багато ходити"),
         "собаки·16°C·вітер": dict(нагода="прогулянка", місце="парк", година=10, темп_c=16, вітер=9, формат="просто неба"),
         "офіс·18°C": dict(нагода="робота", місце="офіс", година=9, темп_c=18, дрес_код="business_casual")}
ТРЕТІ = ("верхній_шар", "прикраси", "пояс", "шарф", "головний_убір", "сережки", "намисто", "кольє", "браслет", "брошка")
вада = lambda о: sorted({z["правило"] for z in о.get("знахідки") or [] if z.get("регістр") == "гейт" and not z.get("свідомий")}
                       | {"слот_двічі" for b in (о.get("структура") or {}).get("блокери") or [] if b.get("код") == "слот_двічі"})
виклик = lambda вх: json.loads(B.виклик("від_моделі", json.dumps(вх, ensure_ascii=False)))
до, після, взято, лишилось = collections.Counter(), collections.Counter(), collections.Counter(), []
for назва, сц in СЦЕНИ.items():
    for сід in (3, 5, 7, 9):
        for рука in "12":
            вх = dict(json.load(open("стенд_вх.json")), сценарій=сц, випадок=назва, сід=сід, **({"донор": True} if рука == "2" else {}))
            r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
            к = r["кандидати_донора"] if (рука == "2" and "донор" in (r.get("поломки_руки_2") or [])) else r["кандидати"]
            в_ = lambda с, i: к[с][i % len(к[с])]["id"] if к.get(с) else None
            тр = [с for с in ТРЕТІ if к.get(с)]
            о = [[x for x in ([в_("сукня", i)] if (к.get("сукня") and i % 2) else [в_("верх", i), в_("низ", i)])
                  + [в_("взуття", i), в_("сумка", i), в_(тр[i % len(тр)], i) if тр else None] if x] for i in range(1, 11)]
            о += [list(dict.fromkeys(x for x in (в_("верх", i), в_("верхній_шар", i), в_("низ", i), в_("взуття", i), в_("сумка", i), в_("прикраси", i)) if x)) for i in range(1, 11)]
            for n, об in enumerate((виклик(dict(вх, ід=о)).get("вердикт") or {}).get("образи") or []):
                if not вада(об):
                    continue
                в1 = виклик(dict(вх, ід=[о[n]], ітерація=2))
                сп = 2 if в1.get("промпт_повноти") else 0
                if сп: в1 = виклик(dict(вх, ід=[о[n]], ітерація=2, спроба_повноти=2, попередній_вердикт=в1["вердикт"]))
                п0, п1 = PL.повнота_набору(в1["вердикт"], кандидати=к, сценарій=сц, дібрати=bool(сп)), в1["повнота"]
                for п in вада((в1["вердикт"]["образи"] or [{}])[0]):
                    до[п] += bool(п0.get("чому")); після[п] += bool(п1.get("чому"))
                    взято[п] += bool((п1.get("ремонт_гейтів") or {}).get("взято"))
                if п1.get("чому"): лишилось.append("%s с%d р%s: %s | %s" % (назва, сід, рука, п1["чому"][:100], п1.get("рядок")))
print("картки з відомим дефектом, коли модель вперта: ДО %s → ПІСЛЯ %s · полагоджено кодом %s" % (dict(до), dict(після), dict(взято)))
print("\n".join("   лишилось: " + x for x in лишилось) or "   лишилось: 0")
