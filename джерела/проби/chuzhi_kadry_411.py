# -*- coding: utf-8 -*-
"""Рядок 411: речі з кадрами ЧУЖИХ речей у каруселі картки — ДО/ПІСЛЯ правила 7 `кадри_речі`.
ДО — правило вимкнено (`чужий_підпис` = None); ПІСЛЯ — як у збірці. ЧУЖА РІЧ = у ряді є кадр,
чий підпис товару (тека / артикул / варіант) інший, ніж у кадру жнив. Друкує по крамницях і
разом: речей із чужими ДО/ПІСЛЯ, знято кадрів, змінено першого кадру, лишилось без кадрів.
Запуск: python3 проби/chuzhi_kadry_411.py [id…]  (з id — друкує ряд ДО/ПІСЛЯ цих речей)"""
import collections, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed as Ф, фід_фото as ФФ, фід_кадр_колір as ФКК
from фід_збагачення import _збагачення_придатне
оф = Ф.читати_yml(Ф.каталог_на_диску("каталог_повний.xml"))[0]
зб, сп, хо = Ф.читати_збагачення(), ФФ._спільні_фото(оф), ФФ._хости_крамниць(оф)
справжнє, к = ФФ.чужий_підпис, ФКК.контекст(оф, зб, сп)
def кадр_картки(o):
    """Той самий кадр-якір, що дає картка (`міст_опис._фото_речі`): кадр кольору речі, інакше кадр жнив."""
    з = зб.get(o["id"]); ок = _збагачення_придатне(з) and not ФФ.чужий_кадр(з.get("фото"), сп.get(o.get("магазин")) or {})
    р = ФКК.рішення(o, з if ок else None, к)
    return р.get("кадр") or (з.get("фото") if isinstance(з, dict) else None)
def ряд(o, правило):
    ФФ.чужий_підпис = справжнє if правило else (lambda u, я: None)
    return ФФ.кадри_речі(o, сп.get(o.get("магазин")) or {}, хо, кадр_картки(o))
с = collections.defaultdict(collections.Counter)
for o in оф:
    до, після, м = ряд(o, False), ряд(o, True), o.get("магазин")
    я = кадр_картки(o)
    ч = lambda р: sum(1 for u in р if я and ФФ._файл_фото(u) != ФФ._файл_фото(я) and справжнє(u, я))
    c = с[м]; c["речей"] += 1; c["чужі ДО"] += bool(ч(до)); c["чужі ПІСЛЯ"] += bool(ч(після))
    c["знято кадрів"] += len(до) - len(після); c["змінено"] += до != після
    c["перший змінено"] += bool(до and після and до[0] != після[0]); c["без кадрів ДО→ПІСЛЯ"] += (not після) - (not до)
    if o["id"] in sys.argv[1:]: print(o["id"], "\n ДО", до, "\n ПІСЛЯ", після)
for м, c in sorted(с.items(), key=lambda x: -x[1]["чужі ДО"]):
    if c["змінено"] or c["чужі ПІСЛЯ"]: print("  %-24s речей %4d · чужі ДО %3d → ПІСЛЯ %d · знято кадрів %4d · перший змінено %d · без кадрів %+d"
        % (м, c["речей"], c["чужі ДО"], c["чужі ПІСЛЯ"], c["знято кадрів"], c["перший змінено"], c["без кадрів ДО→ПІСЛЯ"]))
р = lambda к: sum(c[к] for c in с.values())
print("РАЗОМ: речей %d · з чужими кадрами ДО %d → ПІСЛЯ %d · знято кадрів %d · змінено речей %d · перший кадр змінено %d · без кадрів %+d"
      % (р("речей"), р("чужі ДО"), р("чужі ПІСЛЯ"), р("знято кадрів"), р("змінено"), р("перший змінено"), р("без кадрів ДО→ПІСЛЯ")))
