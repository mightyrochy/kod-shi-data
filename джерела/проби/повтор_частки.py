# -*- coding: utf-8 -*-
"""Д-1: яку ЧАСТКУ повторів пояснює кожна причина — виміряно, не припущено.

Та сама сцена п'ятьма сідами (10 пулів). (1) ТІСНОТА СЛОТА: чим більшу частку
доступного слот віддає за раз (квота ÷ доступно), тим частіше та сама річ вертається.
(2) ЦІНОВИЙ ЯКІР: до В-1 у групі (страта × магазин) `_розкидом` ставив першою найдешевшу
незалежно від сіда; з В-1 ціни семплер не читає, і вороття найдешевшої = глибшої (великі слоти).
«Вороття» — у скількох із 10 пулів річ з'явилась, рахуючи лише ті, що з'явились.
Прогін: python3 проби/повтор_частки.py     (~2 хв: п'ять повних збирань)
"""
import collections, json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed as Ф, bridge as B, міст_пакет as МП, семплер as СМ
доступ, _вибрати = {}, СМ.вибрати
СМ.вибрати = lambda к, б, **кв: (доступ.setdefault("пул", к), _вибрати(к, б, **кв))[1]   # вхід зрізу
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), каталог=Ф.каталог_на_диску("каталог_повний.xml"))
пули = []
for сід in (1, 7, 42, 4242, 31337):
    json.loads(B.виклик("запити", json.dumps(dict(вх, сід=сід), ensure_ascii=False)))
    пули += [{r.get("id") for v in п["кандидати"].values() for r in v}
             for п in МП._КЕШ_ПАКЕТА.values() if п.get("кандидати")]
СМ.вибрати = _вибрати
квоти = {с: len(v) for с, v in [p for p in МП._КЕШ_ПАКЕТА.values() if p.get("кандидати")][0]["кандидати"].items()}
лічба, тіснота, ранги = collections.Counter(i for п in пули for i in п), collections.defaultdict(list), collections.defaultdict(list)
for с, речі in доступ["пул"].items():
    ч = квоти.get(с, 0) / len(речі)
    смуга = "1 ≥ 0.9 слот цілком" if ч >= 0.9 else "2 · 0.5–0.9" if ч >= 0.5 else "3 · 0.2–0.5" if ч >= 0.2 else "4 · < 0.2 великий слот"
    групи = collections.defaultdict(list)
    for r in речі: групи[(СМ._страта(r), СМ._магазин(r))].append(r)
    for г in групи.values():
        for ранг, r in enumerate(sorted(г, key=lambda r: float(r.get("ціна") or 0))):
            тіснота[смуга].append(r.get("id"))
            if ч < 0.2:
                ранги["5 найдешевша в групі" if ранг == 0 else "6 глибша в групі"].append(r.get("id"))
print("%d пулів; доступно %d речей, у пулі %d" % (len(пули), sum(map(len, доступ["пул"].values())), sum(квоти.values())))
print("%-24s %9s %8s %11s %10s" % ("смуга квота ÷ доступно", "доступно", "бачили", "вороття", "у всіх 10"))
for назва, свої in sorted(тіснота.items()) + sorted(ранги.items()):
    були = [лічба[i] for i in свої if лічба[i]]
    print("%-24s %9d %8d %7.1f з %d %9d" % (назва, len(свої), len(були), (sum(були) / len(були)) if були
          else 0, len(пули), sum(1 for i in свої if лічба[i] == len(пули))))
