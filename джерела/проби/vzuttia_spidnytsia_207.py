    for рука, к in (("1", r.get("кандидати") or {}), ("2", r.get("кандидати_донора") or {})):
        вз = к.get("взуття") or []
        т = C.Counter(str(x.get("тип")) for x in вз)
        десять = C.Counter(str(вз[i % len(вз)].get("тип")) for i in range(10)) if вз else {}
