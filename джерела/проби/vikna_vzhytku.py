# -*- coding: utf-8 -*-
"""Л-10: вікна вжитку слів кольору (`verify.ВЖИТОК`) — перерахунок із каталогу тим самим методом
(`verify.вікно_з_вжитку`) і звірка з таблицею. Точки — дизайни (кадр жнив), чиє поле кольору — одна частина
з одним кольором, колір — hex жнив v2 з кадру, що не є спільною картинкою крамниці.
ДОВІРЕНА ПАРА (2.11, рядок 5663): слово крамниці ↔ вимір кадру, що доведено належить цій речі за байтами
(`фід_власник_кадру.запис` — «свій»); «спільний» і «невідомо» вікно не вчать: вони й були чужими варіантами.
Запуск: cd джерела && python3 проби/vikna_vzhytku.py [--таблиця] [--усі] [--записати]
   --таблиця — друкує рядки таблиці; --усі — як ДО 2.11 (кадр, чия власність не доведена, теж вчить);
   --записати — переписує згенерований блок `verify.ВЖИТОК_РЯДКИ` виходом методу лише з доведених варіантів,
   також при `--усі`: кожне слово з довіреними дизайнами (вікно методу без зерна й підлоги лексикону, 14314) — і лише воно, без
   затиску старим вікном і без ручних рядків (паспорт `Річ-колір-межі`, клас п.4; крок 28, дошка 14223);
   --записати-форму — переписує `verify.ФОРМА_ВЖИТКУ` (форма вікна слова: ті самі точки в його вікні
   `ЛЕКСИКОН` без викидів, `verify.форма_з_вжитку`; рішення менеджера 07.11, 14005); без ключа — звірка."""
import ast, collections, os, re, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_розбір as FR, фід_збагачення as FZ, verify as V, colorspace as CS
from фід_власник_кадру import запис as _власник
from фід_фото import спільні_фото as _спільні_фото, чужий_кадр, файл_фото as _файл_фото; from фід_розбір import СЕП_КОЛЬОРУ as _СЕП_КОЛЬОРУ
оф = FR.читати_yml(feed.каталог_на_диску())[0]; зб, сп = FZ.читати_збагачення(), _спільні_фото(оф)
ТОК = re.compile(r"[a-zа-яёєіїґ']+")
одне = lambda ч: not re.search(r"[\[(]", ч) and sum(1 for x in ТОК.findall(ч.lower().replace("-", " "))
                                                     if V.назва_кольору(x) or V.слово_крамниці(x)) <= 1
т = collections.defaultdict(dict)
import колір_річ as _КОЛІР
for o in оф:
    z = зб.get(o["id"]); ч = [x.strip() for x in _СЕП_КОЛЬОРУ.split(o.get("колір_сирий") or o.get("колір_назва") or "") if x.strip()]
    if not FZ.збагачення_придатне(z) or (z.get("версія") or 1) < 2 or len(ч) != 1 or not одне(ч[0]):
        continue
    lab, ск = FZ.lab_з_hex(_КОЛІР.hex_кольору(z["колір_основний"])), V.слово_крамниці(ч[0])
    власник = _власник(o, z) or {}
    довірена = ("--усі" in sys.argv and "--записати" not in sys.argv) or (власник.get("стан") == "свій" and власник["варіант"] != "невідомо")
    if lab is not None and ск and довірена and not чужий_кадр(z.get("фото"), сп.get(o.get("магазин") or o["id"].split("@")[-1]) or {}):
        т[ск["ім"]].setdefault(_файл_фото(z["фото"]), CS.lch(lab))
нові, мало, рядки, вікна = {}, [], [], {}
for сл in V.СЛОВА:
    if сл in V.МЕТАЛИ:
        continue
    нв, лч = V.вікно_з_вжитку(list(т.get(сл, {}).values()))
    if нв is None:
        continue
    вікна[сл] = нв
    if лч["точок"] < V.ВЖИТОК_МІН:
        мало.append("%s %d" % (сл, лч["точок"]))
    нові[сл] = " ".join("-" if x is None else str(x) for x in нв[:4] + tuple(нв[4] or (None,))) + " %d" % лч["точок"]
    рядки.append((сл, нові[сл], "%d: нейтр. %d (+%d поза дугою), поза дугою %d, викидів %d; огорта L%d–%d C%d–%d%s" % (
        лч["дизайнів"], лч["нейтральних"], лч["нп_поза_дугою"], лч["поза_дугою"], лч["викидів"], *лч["огорта"],
        ", тон %d–%d" % лч["дуга_вжитку"] if лч["дуга_вжитку"] else "")))
    if "--таблиця" in sys.argv:
        print(' %-16s %-28s # %s' % ('"%s":' % сл, '"%s",' % рядки[-1][1], рядки[-1][2]))
print("ФАКТ · дизайнів у вжитку %d (слів %d); вікно методу — %d слів; таблиця verify.ВЖИТОК %s" % (
    sum(len(x) for x in т.values()), len(т), len(нові), "збігається" if нові == V.ВЖИТОК_РЯДКИ
    else "РОЗХОДИТЬСЯ: %s" % sorted(set(нові.items()) ^ set(V.ВЖИТОК_РЯДКИ.items()))))
print("ФАКТ · вікна «не певні» (< %d точок огорти): %s; без довірених дизайнів (вікна нема): %s" % (
    V.ВЖИТОК_МІН, ", ".join(мало), ", ".join(сл for сл in V.СЛОВА if сл not in нові)))
форми = {}
for сл, в in вікна.items():
    ф = V.форма_з_вжитку(list(т.get(сл, {}).values()), в)
    if ф:
        форми[сл] = ";".join("%d %d %d" % p for p in ф)
print("ФАКТ · форма вікна (≥ %d точок у вікні методу): %s; таблиця verify.ФОРМА_ВЖИТКУ %s" % (
    V.ВЖИТОК_МІН, ", ".join("%s %d" % (сл, р.count(";") + 1) for сл, р in форми.items()),
    "збігається" if форми == V.ФОРМА_ВЖИТКУ else "РОЗХОДИТЬСЯ: %s" % sorted(set(форми) ^ set(V.ФОРМА_ВЖИТКУ)
                                                                         or [к for к in форми if форми[к] != V.ФОРМА_ВЖИТКУ[к]])))
if "--записати-форму" in sys.argv and "--усі" not in sys.argv:
    код = open("verify.py", encoding="utf-8").read()
    початок = код.index("ФОРМА_ВЖИТКУ = {\n") + len("ФОРМА_ВЖИТКУ = {\n"); кінець = код.index("}\n", початок)
    рядки_ф = []
    for сл, р in форми.items():
        ч = р.split(";")
        рядки_ф.append(' "%s": (' % сл)
        for i in range(0, len(ч), 12):
            рядки_ф.append('  "%s%s"' % (";".join(ч[i:i + 12]), ";" if i + 12 < len(ч) else ""))
        рядки_ф[-1] += "),"
    open("verify.py", "w", encoding="utf-8").write(код[:початок] + "\n".join(рядки_ф) + "\n" + код[кінець:])
    print("ЗАПИСАНО · verify.ФОРМА_ВЖИТКУ: %d слів" % len(форми))
if "--записати" in sys.argv:
    # увесь блок між мітками пише метод: вікно кожного слова, що відрізняється від лексикону, — і лише воно
    код = open("verify.py", encoding="utf-8").read()
    початок = код.index(V.ВЖИТОК_ПОЧАТОК) + len(V.ВЖИТОК_ПОЧАТОК); кінець = код.index(V.ВЖИТОК_КІНЕЦЬ, початок)
    блок = ["ВЖИТОК_РЯДКИ = {"] + [' "%s": "%s",  # %s' % р for р in рядки] + ["}"]
    open("verify.py", "w", encoding="utf-8").write(код[:початок] + "\n".join(блок) + "\n" + код[кінець:])
    print("ЗАПИСАНО · verify.ВЖИТОК_РЯДКИ: %d слів (вихід методу, без зерна й підлоги лексикону)" % len(рядки))
