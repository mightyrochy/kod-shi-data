"""Л-10: вікна вжитку слів кольору (`verify.ВЖИТОК`) — перерахунок із каталогу тим самим методом
(`verify.вікно_з_вжитку`) і звірка з таблицею. Точки — дизайни (кадр жнив), чиє поле кольору — одна частина
з одним кольором, колір — hex жнив v2 з кадру, що не є спільною картинкою крамниці.
ДОВІРЕНА ПАРА (2.11, рядок 5663): слово крамниці ↔ вимір кадру, що доведено належить цій речі за байтами
(`фід_власник_кадру.запис` — «свій»); «спільний» і «невідомо» вікно не вчать: вони й були чужими варіантами.
Запуск: cd джерела && python3 проби/vikna_vzhytku.py [--таблиця] [--усі] [--записати]
   --таблиця — рядки для verify.py; --усі — як ДО 2.11 (кадр, чия власність не доведена, теж вчить);
   --записати — переписує таблицю `verify.ВЖИТОК` цим самим методом (одна дія, без ручних правок)."""
import ast, collections, os, re, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_розбір as FR, фід_збагачення as FZ, verify as V, colorspace as CS
from фід_власник_кадру import запис as _власник
from фід_фото import спільні_фото as _спільні_фото, чужий_кадр, файл_фото as _файл_фото; from фід_розбір import СЕП_КОЛЬОРУ as _СЕП_КОЛЬОРУ
оф = FR.читати_yml(feed.каталог_на_диску())[0]; зб, сп = FZ.читати_збагачення(), _спільні_фото(оф)
ТОК = re.compile(r"[a-zа-яёєіїґ']+")
одне = lambda ч: not re.search(r"[\[(]", ч) and sum(1 for x in ТОК.findall(ч.lower().replace("-", " "))
                                                     if V.назва_кольору(x) or V.слово_крамниці(x)) <= 1
т = collections.defaultdict(dict)
for o in оф:
    z = зб.get(o["id"]); ч = [x.strip() for x in _СЕП_КОЛЬОРУ.split(o.get("колір_сирий") or o.get("колір_назва") or "") if x.strip()]
    if not FZ.збагачення_придатне(z) or (z.get("версія") or 1) < 2 or len(ч) != 1 or not одне(ч[0]):
        continue
    lab, ск = FZ.lab_з_hex(z["колір_основний"].get("hex")), V.слово_крамниці(ч[0])
    довірена = "--усі" in sys.argv or (_власник(o, z) or {}).get("стан") == "свій"
    if lab is not None and ск and довірена and not чужий_кадр(z.get("фото"), сп.get(o.get("магазин") or o["id"].split("@")[-1]) or {}):
        т[ск["ім"]].setdefault(_файл_фото(z["фото"]), CS.lch(lab))
нові, мало, рядки = {}, [], []
for сл, в in V.ЛЕКСИКОН.items():
    if сл in V.МЕТАЛИ:
        continue
    нв, лч = V.вікно_з_вжитку(list(т.get(сл, {}).values()), в)
    if нв is None:
        continue
    if "огорта" not in лч:
        мало.append("%s %d" % (сл, лч["дизайнів"] - лч["поза_дугою"]))
    if tuple(нв) != tuple(в):
        нові[сл] = нв
        if "--таблиця" in sys.argv or "--записати" in sys.argv:
            рядки.append(' %-15s %-27s # %d: нейтр. %d (+%d поза дугою), поза дугою %d, викидів %d; %s%s' % (
                '"%s":' % сл, "%s," % (нв,), лч["дизайнів"], лч["нейтральних"], лч["нп_поза_дугою"],
                лч["поза_дугою"], лч["викидів"],
                "огорта L%d–%d C%d–%d" % лч["огорта"] if "огорта" in лч else "межі лексикону",
                ", тон %d–%d" % лч["дуга_вжитку"] if лч["дуга_вжитку"] else ""))
            if "--таблиця" in sys.argv:
                print(рядки[-1])
print("ФАКТ · дизайнів у вжитку %d (слів %d); вікно вжитку ширше за лексикон — %d слів; таблиця verify.ВЖИТОК %s" % (
    sum(len(x) for x in т.values()), len(т), len(нові), "збігається" if нові == {к: tuple(v) for к, v in V.ВЖИТОК.items()}
    else "РОЗХОДИТЬСЯ: %s" % sorted(set(нові.items()) ^ set((к, tuple(v)) for к, v in V.ВЖИТОК.items()))))
print("ФАКТ · слова, чиї межі L*/C* лишились лексиконові (< %d дизайнів у дузі), — дуга в них однаково з вжитку: %s"
      % (V.ВЖИТОК_МІН, ", ".join(мало)))
if "--записати" in sys.argv:
    # рядок за рядком: коментарі-пояснення між рядками таблиці лишаються; слова, що втратили довірені
    # точки (вікно знову лексиконове), виходять з таблиці; нові — стають у кінець
    код = open("verify.py", encoding="utf-8").read()
    початок = код.index("ВЖИТОК = {\n") + len("ВЖИТОК = {\n"); кінець = код.index("\n}\n", початок) + 1
    def не_ширше(стара, нова, ключ, вікна):
        """Довірені пари звужують вікно, а не розширюють: межі L*/C* не виходять за чинну таблицю, а дуга
        лишається чинною, коли нова її не вміщується (дрейф каталогу з часу останнього запису не
        розширює вікно мовчки: бузковий L до 100 пустив би білий кадр у «бузковий»)."""
        ст = ast.literal_eval(стара[стара.index("(", стара.index(":")): стара.index("),", стара.index(":")) + 1])
        нв = list(вікна[ключ])
        нв[0], нв[1], нв[2], нв[3] = max(нв[0], ст[0]), min(нв[1], ст[1]), max(нв[2], ст[2]), min(нв[3], ст[3])
        def в_дузі(к, д):
            return д is None or (к - д[0]) % 360 <= (д[1] - д[0]) % 360
        if ст[4] and (нв[4] is None or not (в_дузі(нв[4][0], ст[4]) and в_дузі(нв[4][1], ст[4]))):
            нв[4] = ст[4]
        нова = нова.replace("%s," % (tuple(вікна[ключ]),), "%s," % (tuple(нв),), 1)
        return нова
    РУЧНІ = {"лимонний"}  # стеля C* 60 — межі лексикону навмисно (коментар над рядком у verify.py)
    нові_р = {р.split(":")[0].strip(' "'): р for р in рядки}; вийшли = []; вихід = []
    for р in код[початок:кінець].split("\n"):
        ключ = р.split(":")[0].strip(' "') if р.startswith(' "') else None
        if ключ is None:
            вихід.append(р)
        elif ключ in РУЧНІ or "нейтр. " not in р:
            вихід.append(р); нові_р.pop(ключ, None)  # ручний рядок (жнива, власний вибір) скрипт не перекриває
        elif ключ in нові_р:
            вихід.append(не_ширше(р, нові_р.pop(ключ), ключ, нові))
        else:
            вийшли.append(ключ)
    вихід = [р for р in вихід if р != ""]  # нові слова таблиця не бере: вікно вжитку лише звужує чинне
    open("verify.py", "w", encoding="utf-8").write(код[:початок] + "\n".join(вихід) + "\n" + код[кінець:])
    print("ЗАПИСАНО · verify.ВЖИТОК: %d слів; вийшли (вікно знову лексиконове): %s; нове слово не додано (лишились лексиконовими): %s" % (
        len(рядки) - len(нові_р), ", ".join(вийшли) or "—", ", ".join(нові_р) or "—"))
