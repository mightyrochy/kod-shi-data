"""Контраст біля обличчя перевіряється і для відомого інтервалу світлоти."""
import sys
from unittest.mock import patch
sys.path.insert(0, ".")
import оцінка_образу as О


def головна():
    """Пропустити темний інтервал через справжній суд світлоти."""
    особа = dict(доступно=True, L_шкіри=80, value_gap=10)
    for тип, очікувано in (("інтервал", True), ("невідомо", False)):
        р = dict(id="темний-верх", слот="верх", колір_тип=тип, lab=None,
                 колір_не_вимір=dict(свідок="shop_word", вікно=(10, 12, 0, 5, None)))
        with patch.object(О._O, "контраст_особи", return_value=особа):
            вих = О._контраст_обличчя({}, {}, [р], "uncontrolled")
        print(тип, "суд контрасту:", вих)
        assert bool(вих.get("пункт")) == очікувано
        if очікувано:
            assert вих["пункт"]["стан"] == "провал"
    р["колір_тип"] = "інтервал"
    р["колір_не_вимір"]["вікно"] = (10, 90, 0, 5, None)
    with patch.object(О._O, "контраст_особи", return_value=особа):
        вих = О._контраст_обличчя({}, {}, [р], "uncontrolled")
    print("Непевний інтервал: без входу", bool(вих.get("без_входу")))
    assert вих.get("без_входу") and not вих.get("пункт")


if __name__ == "__main__":
    головна()
