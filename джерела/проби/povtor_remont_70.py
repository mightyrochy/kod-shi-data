# Т-7: образи промпту — «вердикт»[].твій_образ (форма на дроті); на main — «образи» як є
образи_промпту = lambda т: [с.get("твій_образ", с) for с in (json.loads(т).get("вердикт") or json.loads(т)["образи"])]


def образи_стенда(пул, скільки):        # сценарна модель `рв6_стенд.js`: пул[слот][i % довжина]
    б = lambda с, i: (пул[с][i % len(пул[с])]["н"] if пул.get(с) else None)
    треті, вих = [с for с in ТРЕТІ if пул.get(с)], []
    for i in range(1, скільки + 1):
        р = ([б('сукня', i)] if (пул.get('сукня') and i % 2) else [б('верх', i), б('низ', i)])
        р += [б('взуття', i), б('сумка', i)] + ([б(треті[i % len(треті)], i)] if треті else [])
        вих.append(dict(ід='о%d' % i, підпис='проба', полюс='вільний', речі=[x for x in р if x]))
    return json_(dict(образи=вих))


