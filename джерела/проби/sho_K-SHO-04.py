"""K-SHO-04 (неперервність лінії ноги).

ДО ПРАВКИ: ID не згадувався в ЖОДНОМУ модулі — «пара, зведена до ноги або до
низу, продовжує лінію; контрастна ріже її» не рахувалось ніде.
ПІСЛЯ: ΔL* пари проти ноги (шкіра або колготки) і проти низу проти `step_min`;
рядок стоїть у `вердикт.образи[0].знахідки`. Проба друкує обидва стани: пара, що
ріже лінію, дає рядок; пара, зведена до низу, — не дає (умова лишилась умовою)."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["назва"]: c for c in B.каталог_останнього_пакета()}
пул = json.loads(з["руки"]["1"])["пул"]
сукня = next(r for r in пул["сукня"] if (кат.get(r["назва"]) or {}).get("lab"))
L_низу, L_шкіри = кат[сукня["назва"]]["lab"][0], 75.8
пари = [(r, кат[r["назва"]]) for r in пул["взуття"] if (кат.get(r["назва"]) or {}).get("lab")]
ріже = max(пари, key=lambda x: min(abs(x[1]["lab"][0] - L_низу), abs(x[1]["lab"][0] - L_шкіри)))
колона = min(пари, key=lambda x: abs(x[1]["lab"][0] - L_низу))
print("сукня L*%.0f «%s» · шкіра L*%.0f" % (L_низу, сукня["назва"][:36], L_шкіри))
for мітка, (пара, c) in (("ріже", ріже), ("колона з низом", колона)):
    вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=json.dumps(
        {"версія": "1", "образи": [{"ід": "о1", "речі": [сукня["н"], пара["н"]]}]},
        ensure_ascii=False)), ensure_ascii=False)))
    зн = ((вм.get("вердикт") or {}).get("образи") or [{}])[0].get("знахідки") or []
    р = next((z for z in зн if z.get("правило") == "K-SHO-04"), None)
    print("%-15s пара L*%2.0f (Δ до низу %2.0f, до ноги %2.0f) → K-SHO-04: %s"
          % (мітка, c["lab"][0], abs(c["lab"][0] - L_низу), abs(c["lab"][0] - L_шкіри),
             "нема (лінія триває)" if not р else "%s %.2f" % (р["сила"], р["сила_нп"])))
