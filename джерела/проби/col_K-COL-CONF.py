# -*- coding: utf-8 -*-
"""K-COL-CONF (конфлікт ремонтів на одному носії) — вимкнено чесно: бракує ДРУГОГО виробника вікна.

Корпус: «два кольорові правила приписують ОДНОМУ предметові вікна цільової
світлоти, які не перетинаються. WHEN: перетин порожній. FORCE: soft, регістр —
репліка. Код НЕ арбітрує». Емітент `колір_образу.несумісні_ремонти` під'єднаний
(`суд_образу.review`: «зн = зн + несумісні_ремонти(зн)») і працює — проба це й
показує прямим викликом. Чого нема — ВХОДУ: тест ПАРНИЙ, а на живому шляху
колірне вікно в каталог віддає рівно ОДНЕ правило (K-KOH-06). Другі виробники
мовчать названо: K-COL-01 і K-COL-06 за гейтом площі (походження площі у фіді
0 %), K-CLR-02 — бо вікно згортається в `реальне_вікно`.
Запуск із теки `джерела`: `python3 проби/col_K-COL-CONF.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import суд_образу as СО, колір_образу as КО, composer as КМ

вх, r, кат, спец = ПВ.стенд(гілка=0)
ід = [x["id"] for с in ("верх", "низ", "взуття", "сумка", "шарф") for x in (r["кандидати"].get(с) or [])[:1]]
за_ід = {c["id"]: c for c in ПВ.B.каталог_останнього_пакета()}
речі = [КМ._у_річ(dict(за_ід[i]), за_ід[i]["слот"], вх.get("тіло")) for i in ід if i in за_ід]
сц = вх["сценарій"]
рез = СО.review(вх.get("особа") or {}, речі, нагода=сц.get("нагода"), дрес_код=сц.get("дрес_код"),
                сцен=сц, темп_c=сц.get("темп_c"))
зн = [z for d in рез["стани"].values() for z in d["знахідки"]]
вікна = [(z["правило"], (z["запит_у_каталог"] or {}).get("слот")) for z in зн
         if any(k in КО._ОСІ_ЗАПИТУ for k in (z.get("запит_у_каталог") or {}))]
print("колірних вікон у каталог: %d від правил %s · носіїв із ДВОМА правилами: %d"
      % (len(вікна), sorted({п for п, _ in вікна}) or "—", СО._пар_вікон(зн)))
пункт = next(p for p in СО.чеклісти(зн, СО.елементи(речі, "у приміщенні"))["надлишок"] if p["пункт"] == 18)
print("ФАКТ · чекліст 18 «%s»: стан «%s», бракує входу «%s»"
      % (пункт["що"], пункт["стан"], пункт["вхід"]))
# МЕХАНІЗМ ЖИВИЙ: дай йому ту пару, якої живий вхід не дає, — він говорить.
пара = КО.несумісні_ремонти([
    dict(правило="K-CLR-02", речі=["шарф"], запит_у_каталог=dict(слот="шарф", цільова_L=[60.0, 80.0])),
    dict(правило="K-KOH-06", речі=["шарф"], запит_у_каталог=dict(слот="шарф", цільова_L=[10.0, 30.0]))])
print("ФАКТ · на парі непересічних вікон: %s" % ПВ.рядок(пара, "K-COL-CONF"))
assert пункт["стан"] == "без входу" and "два колірні вікна" in пункт["вхід"], пункт
assert СО._пар_вікон(зн) == 0 and len({п for п, _ in вікна}) <= 1, вікна
z = next(x for x in пара if x["правило"] == "K-COL-CONF")
assert z["сила"] == "soft" and z["регістр"] == "репліка", z     # корпусна сила
assert len(z["ремонт"]) == 4 and "рознести цілі" in z["ремонт"][-1], z   # код не арбітрує
