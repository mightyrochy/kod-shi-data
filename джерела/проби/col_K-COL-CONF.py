# -*- coding: utf-8 -*-
"""K-COL-CONF (конфлікт ремонтів на одному носії) — вхід є, конфлікту нема: правила сходяться.

Корпус: «два кольорові правила приписують ОДНОМУ предметові вікна цільової
світлоти, які НЕ перетинаються. WHEN: перетин порожній. FORCE: soft, регістр —
репліка. Код НЕ арбітрує: знахідка називає носія, обидва ремонти й третій вихід».
ЩО ЗМІНИЛОСЬ 18.09.2026. Доти вхід був відсутній: колірне вікно в каталог
віддавало рівно ОДНЕ правило (K-KOH-06), а тест парний. Збагачення каталогу
(колір пулу 0 → 92 %) оживило K-CLR-02 — і пара на «шарф» зʼявилась. Але вона
ПЕРЕТИНАЄТЬСЯ (L*[48,76] ∩ L*[20,80]), тобто це дзеркальний бік: K-COL-JOIN, не
K-COL-CONF. Тому пункт 18 чекліста читає «пройдено», а не «без входу», і мовчання
K-COL-CONF тут — це відповідь, а не німота.
Запуск із теки `джерела`: `python3 проби/col_K-COL-CONF.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import суд_образу as СО, колір_образу as КО, composer as КМ

сц = dict(нагода="робота", місце="офіс", година=9, темп_c=18, дрес_код="business_casual")
вх, r, кат, спец = ПВ.стенд(гілка=0, сценарій=сц)
F, *_ = ПВ.B._features(вх)          # та сама особа, якою ходить живий шлях
за_ід = {c["id"]: c for c in ПВ.B.каталог_останнього_пакета()}
ід = [(r["кандидати"].get(с) or [None])[1 % max(1, len(r["кандидати"].get(с) or [1]))]
      for с in ("верх", "низ", "взуття", "сумка", "шарф", "прикраси")]
речі = [КМ._у_річ(dict(за_ід[x["id"]]), за_ід[x["id"]]["слот"], вх.get("тіло")) for x in ід if x]
рез = СО.review(F, речі, нагода=сц["нагода"], дрес_код=сц["дрес_код"], сцен=сц, темп_c=18)
зн = [z for d in рез["стани"].values() for z in d["знахідки"]]
вікна = sorted({(z["правило"], (z["запит_у_каталог"] or {}).get("слот")) for z in зн
                if any(k in КО._ОСІ_ЗАПИТУ for k in (z.get("запит_у_каталог") or {}))})
print("колірні вікна в каталог: %s · носіїв із ПАРОЮ правил: %d"
      % (", ".join("%s→%s" % в for в in вікна), СО._пар_вікон(зн)))
пункт = next(p for p in СО.чеклісти(зн, СО.елементи(речі, "у приміщенні"))["надлишок"]
             if p["пункт"] == 18)
print("ФАКТ · чекліст 18 «%s»: стан «%s» (вхід «%s»)" % (пункт["що"], пункт["стан"], пункт["вхід"]))
assert СО._пар_вікон(зн) > 0 and пункт["стан"] == "пройдено", (СО._пар_вікон(зн), пункт)
assert not any(z["правило"] == "K-COL-CONF" for z in зн), "вікна перетинаються — конфлікту нема"
# МЕХАНІЗМ ЖИВИЙ: дай йому НЕПЕРЕСІЧНУ пару — він говорить.
пара = КО.несумісні_ремонти([
    dict(правило="K-CLR-02", речі=["шарф"], запит_у_каталог=dict(слот="шарф", цільова_L=[60.0, 80.0])),
    dict(правило="K-KOH-06", речі=["шарф"], запит_у_каталог=dict(слот="шарф", цільова_L=[10.0, 30.0]))])
print("ФАКТ · на НЕПЕРЕСІЧНІЙ парі: %s" % ПВ.рядок(пара, "K-COL-CONF"))
z = next(x for x in пара if x["правило"] == "K-COL-CONF")
assert z["сила"] == "soft" and z["регістр"] == "репліка", z              # корпусна сила
assert len(z["ремонт"]) == 4 and "рознести цілі" in z["ремонт"][-1], z   # код не арбітрує
