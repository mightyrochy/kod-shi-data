"""Повний каталог × тіла, особи, колготки й смуги для чотирьох суддів `аксесуари_взуття` (вага Е3)."""
import gzip, json, os, pathlib


def набори():
    """Входи без моделі: граничні краї біля литки; кожна пара й кожен низ каталогу з представниками іншого боку."""
    import fit as F, сценарій as С, trace as Т, аксесуари_взуття as A
    with gzip.open(pathlib.Path(os.environ['TMP']) / 'е3_каталог.json.gz', 'rt', encoding='utf-8') as ф:
        к = sorted(json.load(ф), key=lambda р: str(р['id']))
    б, слот = dict(плечі=98, груди=92, талія=74, стегна=99), lambda *с: [р for р in к if р.get('слот') in с]
    тіла = [F.тіло(з, dict(б, **(dict(коліно=к_, литка=л) if л else {}))) for з, к_, л in   # литка: не міряна, вужча, ширша
            ((168, 0, 0), (168, 37.0, 35.0), (168, 37.0, 38.0), (158, 35.0, 37.0), (178, 38.0, 39.0), (168, 37.0, 40.0), (168, 36.0, 42.0))]
    for т in (dict(t, похибка_ширин=dict.fromkeys(t['похибка_ширин'], 0.0)) for t in тіла[2:]):   # граничні: нульова похибка ширин
        for d, h in ((x / 4, т['висоти']['литка']) for x in range(-40, 41)):
            for р in (dict(слот='взуття', id='ч', назва='ч', халява_см=h + d), dict(слот='низ', тип='спідниця', id='с', верх_см=h + 70, низ_см=h + d)):
                yield 'гран%s@%s+%.2f' % (р['id'], т['обхвати'].get('литка'), d), 'халява_і_поділ', [т, [р]], {}
    пари, низи, тіла = слот('взуття'), слот('низ', 'сукня', 'комплект'), тіла[:5]
    по_групі = lambda речі, ключ: (lambda гр: [гр[x] for x in sorted(гр, key=str)])({ключ(р): р for р in reversed([р for р in речі if A.L(р) is not None])})
    реп_н = по_групі(низи, lambda р: (A.гола_нога([р]), round(A.L(р)[0] / 20)))
    реп_п = по_групі([р for р in пари if р.get('виріз_стопи')], lambda р: (р['виріз_стопи'], round(A.L(р)[0] / 20)))
    колготи = [dict(р, слот='колготи', id='колг-' + str(р['id']), den=40) for р in реп_н[::3]]
    особи, ід = [None, dict(L_шкіри=45.0), dict(L_шкіри=75.8)], lambda xs: '+'.join(str(x['id']) for x in xs)
    вид_н = [[н] for н in реп_н if A.гола_нога([н])][:1] + [[н] for н in реп_н if A.гола_нога([н]) is False][:1] + [[]]
    print('пари', len(пари), 'низи', len(низи), 'реп', len(реп_н), len(реп_п), 'колготи', len(колготи), flush=True)
    for р in пари + низи + слот('верхній_шар'):
        for і, t in enumerate(тіла): yield '%s@т%d' % (р['id'], і), 'халява_і_поділ', [t, [р]], {}
        yield str(р['id']), 'взуття_і_поділ', [тіла[0], [р]], {}
        Т.ЗАПИСИ.clear()
    for п in пари:
        for речі in [[п, н] for н in реп_н] + [[п]]:
            for і, о in enumerate(особи): yield ід(речі) + '@о%d' % і, 'лінія_ноги', [речі], dict(особа=о)
            for кг in колготи: yield ід(речі + [кг]), 'лінія_ноги', [речі + [кг]], dict(особа=особи[2])
        for речі in ([п] + н + кг for н in вид_н for кг in [[]] + [[dict(колготи[0], den=d)] for d in (None, 20, 60, 100)]):
            for смуга in list(С.СМУГИ_ПОГОДИ) + [None]:
                yield ід(речі) + '/den%s@%s' % (речі[-1].get('den'), смуга), 'видимість_краю', [речі], dict(смуга_погоди=смуга)
        Т.ЗАПИСИ.clear()
    for н in низи:
        for п in реп_п: yield ід([п, н]), 'лінія_ноги', [[п, н]], dict(особа=особи[2])
        Т.ЗАПИСИ.clear()
