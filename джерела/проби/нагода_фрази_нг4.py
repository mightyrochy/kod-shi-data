# -*- coding: utf-8 -*-
"""НГ-4: 40 фраз (`нагода_фрази_нг4.json`) → хід розмови з живою моделлю → шов → паспорт v2. Друкує частку фраз, де
впізнано вид (other — ще й `like`) і всі виміри з її слів, і чи та сама фраза двічі дає той самий паспорт (рядок 238; розбивка — нагода/місце окремо від ошатності моделі).
Без моделі — нічого не міряє. Запуск: cd джерела && ZHYVA=sonnet [PAR=8] python3 проби/нагода_фрази_нг4.py"""
import json, os, sys
from concurrent.futures import ThreadPoolExecutor
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import мова_спільне as С
М, Ф = С.М, json.load(open(os.path.join(С.ТУТ, "нагода_фрази_нг4.json"), encoding="utf-8"))
if not С.МОДЕЛЬ:
    sys.exit("без моделі вимірювати нічого: ZHYVA=sonnet або MODEL=…")
збої = []
def паспорт(фраза):
    р = М.прийняти_розмову(С.модель(М.промпт_розмови({"розмова": {"нове": фраза, "історія": []}, "сценарій": {}, "паспорт": {}}))[0])
    збої.extend([фраза[:30] + ": " + р["причина"]] if р["причина"] else [])
    п = json.loads(М.мова({"паспорт_з": р["внутрішня"], "сценарій": {}, "паспорт": {}, "слова_розмови": [фраза],
                           "частини": р["частини"] or {"need": "none"}}))["паспорт"]
    return dict({к: п.get(к) for к in ("нагода", "місце", "дрес_код", "письмово")}, **п["виміри"]), п["звідки"]
def так(ф, п):
    в, з = п
    вид = в["kind"] in ф["вид"] and (в["kind"] != "other" or в["like"] in (ф["like"] or []))
    чого = [к for к, ч in ф["виміри"].items() if not (
        (len(в["parts"]) >= ч and з["parts"] == "her_words") if к == "parts" else
        ч in (в["письмово"] or []) if к == "written" else
        (в[к] == ч and з[к] in ("her_words", "written")))]
    зайві = [к for к in ("role", "audience", "religious_place", "reserved_colour", "volume") if з[к] == "her_words" and к not in ф["виміри"]]
    return вид, чого + ["+" + к for к in зайві]
with ThreadPoolExecutor(int(os.environ.get("PAR") or 8)) as пул:
    пари = list(пул.map(lambda ф: (паспорт(ф["фраза"]), паспорт(ф["фраза"])), Ф))
вид_т = вим_т = разом = однакові = нм = ош = 0; зайвих = []
for ф, (а, б) in zip(Ф, пари):
    вид, чого = так(ф, а); зайвих.extend(к for к in чого if к[0] == "+"); бракує = [к for к in чого if к[0] != "+"]
    вид_т += вид; вим_т += not бракує; разом += вид and not бракує
    інакше = sorted(к for к in а[0] if (а[0][к], а[1].get(к)) != (б[0][к], б[1].get(к))); однакові += not інакше
    нм += bool(set(інакше) & {"нагода", "місце"}); ош += set(інакше) <= {"formality"} and bool(інакше)
    print("%s%s %-52s kind=%s like=%s%s%s" % ("✓" if вид and not бракує else "✗", "≠" if інакше else "=", ф["фраза"][:52], а[0]["kind"],
          а[0]["like"], " · виміри (бракує / +понад очікуване): " + ",".join(чого) if чого else "", " · двічі різне: " + ",".join(інакше) if інакше else ""))
print("модель %s · фраз %d · вид %d/%d · виміри з її слів %d/%d · вид і виміри %d/%d · двічі той самий паспорт %d/%d"
      % (С.МОДЕЛЬ, len(Ф), вид_т, len(Ф), вим_т, len(Ф), разом, len(Ф), однакові, len(Ф)) + " · вимірів понад очікуване %d" % len(зайвих) + " · з них нагода/місце різні %d, лише formality %d" % (нм, ош) + " · збоїв відповіді %d %s" % (len(збої), збої or ""))
