# -*- coding: utf-8 -*-
"""НГ-4: 40 фраз (`нагода_фрази_нг4.json`) → хід розмови з живою моделлю → шов → паспорт. Міряє лише поля, які паспорт
ще несе (рядок 1071): нагода, місце, дрес-код, ошатність, частина дня, зарезервований колір, відкриті зони. Друкує, чи
нагода чи місце — одне з очікуваних (32 фрази; решта — «інше», не міряється) і чи названі поля такі, як очікувано, і чи
та сама фраза двічі дає ті самі поля (рядок 238; розбивка: нагода/місце, лише ошатність, лише частина дня).
Без моделі — нічого не міряє. Запуск: cd джерела && ZHYVA=sonnet [PAR=8] python3 проби/нагода_фрази_нг4.py"""
import json, os, sys
from concurrent.futures import ThreadPoolExecutor
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import мова_спільне as С
М, Ф = С.М, json.load(open(os.path.join(С.ТУТ, "нагода_фрази_нг4.json"), encoding="utf-8"))
ПОЛЯ = ("occasion", "place", "dress_code", "formality", "part_of_day", "reserved_colour", "open_zones")
if not С.МОДЕЛЬ:
    sys.exit("без моделі вимірювати нічого: ZHYVA=sonnet або MODEL=…")
збої = []
def паспорт(фраза):
    р = М.прийняти_розмову(С.модель(М.промпт_розмови({"розмова": {"нове": фраза, "історія": []}, "сценарій": {}, "паспорт": {}}))[0])
    збої.extend([фраза[:30] + ": " + р["причина"]] if р["причина"] else [])
    п = json.loads(М.мова({"паспорт_з": р["внутрішня"], "сценарій": {}, "паспорт": {}, "слова_розмови": [фраза],
                           "частини": р["частини"] or {"need": "none"}}))["паспорт"]
    в, з = С.ПН.виміри_нагоди(п, {})       # наново: типове коду (день, звичайна аудиторія) — не її поле
    return {к: (в[к] if з[к] not in ("default", "unknown") else None) for к in ПОЛЯ}
with ThreadPoolExecutor(int(os.environ.get("PAR") or 8)) as пул:
    пари = list(пул.map(lambda ф: (паспорт(ф["фраза"]), паспорт(ф["фраза"])), Ф))
влучно = поля_т = однакові = нм = ош = пд = 0
for ф, (а, б) in zip(Ф, пари):
    наг = not ф["нагода"] or bool({а["occasion"], а["place"]} & set(ф["нагода"].split()))
    хиби = ["%s=%s" % (к, а[к]) for к, ч in ф["поля"].items() if а[к] != ч]
    влучно += наг; поля_т += not хиби
    інакше = sorted(к for к in ПОЛЯ if а[к] != б[к]); однакові += not інакше
    нм += bool(set(інакше) & {"occasion", "place"}); ош += інакше == ["formality"]; пд += інакше == ["part_of_day"]
    print("%s%s %-48s %s/%s ош%s %s%s%s" % ("✓" if наг and not хиби else "✗", "≠" if інакше else "=", ф["фраза"][:48], а["occasion"], а["place"],
          а["formality"], а["part_of_day"] or "", " · поля: " + ",".join(хиби) if хиби else "",
          " · двічі різне: " + ",".join("%s %s|%s" % (к, а[к], б[к]) for к in інакше) if інакше else ""))
print("модель %s · фраз %d · нагода/місце влучно %d/%d (міряно %d) · поля як очікувано %d/%d · двічі ті самі поля %d/%d · з них нагода/місце "
      "різні %d, лише formality %d, лише part_of_day %d · збоїв відповіді %d %s" % (С.МОДЕЛЬ, len(Ф), влучно, len(Ф), sum(1 for ф in Ф if ф["нагода"]),
      поля_т, len(Ф), однакові, len(Ф), нм, ош, пд, len(збої), збої or ""))
