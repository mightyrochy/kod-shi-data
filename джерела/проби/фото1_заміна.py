"""ФОТО-1 (CLAUDE.md п.17): чи крок опису з фото пропонує заміну, на яких підставах і що вирішує код.
(1) записані виклики стенда (файли ZVIT_OUT, .txt чи .gz, аргументами): скільки описів запропонували
`swap`, підстави, рішення коду з діагнозу руки; (2) підставний шов на мості (`стенд_вх.json`, сід 3): звичайна
відповідь — заміни нема; «фото не та річ» (як рядок 757: верх, colour) — запасні, другий опис, склад картки.
Друкує факт. Запуск: cd джерела && python3 проби/фото1_заміна.py [вердикти.txt …]"""
import sys, os, json, gzip, re, tempfile, collections
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge as B, feed as F
описів, підстави, рішення = 0, collections.Counter(), collections.Counter()
for ф in sys.argv[1:]:
    д = json.load((gzip.open if ф.endswith(".gz") else open)(ф, "rt", encoding="utf-8"))
    for в in (x for п in д["прогони"] for x in п["вердикти"]):
        for к in (в.get("етапи") or {}).get("виклики") or []:
            if str((к.get("запит") or {}).get("чого", "")).startswith("description"):
                описів += 1; м = re.search(r'"swap"\s*:\s*\{[^}]*"why"\s*:\s*"(\w+)"', str(к.get("відповідь_сира")))
                підстави[м.group(1) if м else "без заміни"] += 1
        for р in (в.get("етапи") or {}).get("діагноз_руки") or []:
            for м in re.finditer(r"photo_swap_(?:proposed|decided) · .*?(?:code|state)=(\w+)", str(р)): рішення[м.group(1)] += 1
print("ФАКТ · записані: описів %d · підстави %s · рішення коду %s" % (описів, dict(підстави), dict(рішення)))
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), каталог=F.каталог_на_диску("каталог_brief.xml"), сід=3)
вх["кеш_кольорів"] = os.path.join(tempfile.gettempdir(), "кеш_живого_шляху.json")
if not os.path.exists(вх["кеш_кольорів"]): json.dump({}, open(вх["кеш_кольорів"], "w"))
міст = lambda ім, d: json.loads(B.виклик(ім, json.dumps(d, ensure_ascii=False)))
пул = міст("запити", вх)["пакети"]["1"]["пул"]
образи = [dict(ід="о%d" % (і + 1), підпис="шов", речі=[пул[с][і]["н"] for с in ("верх", "низ", "взуття", "сумка", "шарф")]) for і in (0, 1)]
в1 = міст("від_моделі", dict(вх, текст_моделі=json.dumps(dict(версія="1", образи=образи), ensure_ascii=False)))
вб = міст("від_моделі", dict(вх, ітерація=2, відповідь="ВИБІР_V1", вибір_над=в1["вибір_над"], текст_моделі='{"версія":"1","обрано":"о1"}'))["вибір"]
верх, оп = вб["ід"][0], dict(вх, ітерація=2, відповідь="ОПИС_ВІДПОВІДЬ_V1", ід=вб["ід"], інші_образи=[о["ід"] for о in в1["образи"]])
відп = lambda **з: json.dumps(dict(version="1", text="t", how_to_wear=[], wrong_photos=[], **з), ensure_ascii=False)
print("ФАКТ · звичайний опис: заміна", міст("від_моделі", dict(оп, текст_моделі=відп())).get("заміна") or "нема")
з = міст("від_моделі", dict(оп, текст_моделі=відп(swap=dict(item=вб["номери"][верх], why="colour"))))["заміна"]
print("ФАКТ · «фото не та річ» (верх, colour): стан %s · запасні %s · відкинуто суддею %d" % (з["стан"], [x["н"] for x in з.get("запасні") or []], len(з.get("відкинуто") or [])))
if з.get("запасні"):
    запит = dict(річ=з["річ"], чому=з["чому"], запасні=[x["id"] for x in з["запасні"]])
    о = міст("опис", dict(вх, речі=вб["ід"], номери={**вб["номери"], **з["номери"]}, заміна=запит))
    print("ФАКТ · другий опис: кадрів %d (образ + запасні) · запасних у промпті %d" % (len(о["фото"]), len(json.loads(о["промпт"])["swap_spares"]["spares"])))
    в5 = міст("від_моделі", dict(оп, заміна_запасні=запит, текст_моделі=відп(swap=dict(item=вб["номери"][верх], why="colour", to=з["запасні"][0]["н"]))))
    print("ФАКТ · рішення: %s · склад картки: %s → %s · рядок жінці %s" % (в5["заміна"]["стан"], верх, [r["id"] for r in в5["речі"] if r["id"] not in вб["ід"]], (в5["заміна"].get("повідомлення") or {}).get("kind")))
