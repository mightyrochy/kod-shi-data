# -*- coding: utf-8 -*-
"""КОЛ-2 (рядок 590): що K-COL-06 (`нейтралі_крос`) каже на образах ЖИВОГО шляху — над файлом вердиктів стенда.

Вхід — `ZVIT_OUT` стенда (`аудит/проби/рв6_стенд.js`, сід 3, каталог_повний); образи — усі `образи_кроку`
рук 1–2. Стан K-COL-06 — за пунктом 20 чекліста надлишку (провал / без входу з `бракує` / пройдено), а де
пункту нема (до КОЛ-2) — «мовчить невидимо»: гейт площ закритий, правило не запускалось. «Судить чи каже
без входу» = провал + пройдено + без входу. Запуск: `python3 проби/кол2_нейтралі_живий_шлях.py <звіт.txt>`."""
import json, sys, collections, re

ПУНКТ = "дві нейтралі на одній світлоті — тон-у-тон або з кроком, не «майже те саме»"
d = json.load(open(sys.argv[1], encoding="utf-8"))
стани, бракує, образів = collections.Counter(), collections.Counter(), 0
for п in d["прогони"]:
    for в in п["вердикти"]:
        if str(в.get("рука")) not in ("1", "2"):
            continue
        for к in (в.get("етапи") or {}).get("виклики") or []:
            for о in к.get("образи_кроку") or []:
                образів += 1
                н = (о.get("чекліст") or {}).get("надлишок") or {}
                вим = [x for x in н.get("вимкнено") or [] if x.get("що") == ПУНКТ]
                if ПУНКТ in (н.get("провал") or []):
                    білі = all("білі" in (z.get("суть") or "") for z in о.get("знахідки") or []
                               if z.get("правило") == "K-COL-06")
                    стани["провал (два різні білі)" if білі else "провал (крос-нейтралі)"] += 1
                elif вим:
                    стани["без входу"] += 1
                    б = вим[0].get("бракує") or ""
                    for поле in set(re.findall(r"поле «([^»]+)»", б)) | ({"вимір_hex_шум"} if "шуму двох кадрів" in б else set()):
                        бракує[поле] += 1
                elif "K-COL-06" in (н.get("правила") or []):
                    стани["пройдено"] += 1
                else:
                    стани["мовчить невидимо (пункту нема)"] += 1
судить = sum(н for s, н in стани.items() if not s.startswith("мовчить"))
print("ФАКТ · образів рук 1–2: %d · K-COL-06 судить чи каже «без входу»: %d (%.0f %%)"
      % (образів, судить, 100.0 * судить / max(1, образів)))
print("ФАКТ · стани K-COL-06: %s" % dict(стани))
for б, н in бракує.most_common(6):
    print("ФАКТ · у «без входу» назване поле «%s» ×%d" % (б, н))
