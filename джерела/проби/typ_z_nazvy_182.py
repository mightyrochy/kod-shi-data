# -*- coding: utf-8 -*-
"""Рядок 182: слот і тип — з тієї назви, яку картка показує жінці.
ДО — класифікація з СИРОЇ назви фіду (як до цієї гілки), ПІСЛЯ — з відновленої (`назва_показу`).
Запуск: cd джерела && python3 проби/typ_z_nazvy_182.py"""
import collections, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_слот as ФС
оф = feed.читати_yml(feed.каталог_на_диску())[0]
з_назвою = [o for o in оф if o.get("назва_показу")]
дж = collections.Counter(o.get("назва_показу_джерело") for o in з_назвою)
розб_т, розб_с, зсув_с = 0, 0, collections.Counter()
типи_до, типи_після = collections.Counter(), collections.Counter()
for o in з_назвою:
    сира = dict(o, назва_показу=None)                      # як судилось ДО гілки
    с0 = ФС.слот(сира); т0 = ФС.тип_речі(сира, с0)
    с1 = ФС.слот(o);    т1 = ФС.тип_речі(o, с1)
    if т0 != т1: розб_т += 1; типи_до[т0] += 1; типи_після[т1] += 1
    if с0 != с1: розб_с += 1; зсув_с[(с0, с1)] += 1
print("ФАКТ · оферів %d · відновлену назву несуть %d · джерела: %s"
      % (len(оф), len(з_назвою), dict(дж)))
print("ФАКТ · РОЗБІЖНІСТЬ «картка проти класифікатора»: ТИП ДО %d → ПІСЛЯ 0 · СЛОТ ДО %d → ПІСЛЯ 0"
      % (розб_т, розб_с))
print("ФАКТ · зсуви слота (ДО→ПІСЛЯ): %s" % зсув_с.most_common())
print("ФАКТ · типи, яких річ позбулась: %s" % типи_до.most_common(8))
print("ФАКТ · типи, яких набула:       %s" % типи_після.most_common(8))
ЗРАЗКИ = ("ж-07573@honchstudio.com", "ж-03000@solmar.com.ua", "ж-05375@feelyou.com.ua")
за_ід = {o["id"]: o for o in оф}
for ід in ЗРАЗКИ:
    o = за_ід.get(ід)
    if o is None:
        print("ФАКТ · %s — у каталозі нема" % ід); continue
    сира = dict(o, назва_показу=None)
    с0 = ФС.слот(сира); с1 = ФС.слот(o)
    print("ФАКТ · %s · «%s» → «%s» · слот %s→%s · тип %s→%s"
          % (ід, (o["назва"] or "")[:34], o["назва_показу"], с0, с1,
             ФС.тип_речі(сира, с0), ФС.тип_речі(o, с1)))
джинси = [o for o in з_назвою if ФС.тип_речі(o, ФС.слот(o)) == "джинси"]
print("ФАКТ · серед речей із відновленою назвою тип «джинси» лишився в %d (усі — справді джинси: %s)"
      % (len(джинси), [o["назва_показу"][:24] for o in джинси][:4]))
