"""Рядок 185: складена назва на картці не суперечить речі.
ДО — іменник брався з оголошеного крамницею типу, ПІСЛЯ — з назви-рубрики, а бракуючі
іменники додано в словник суду. Запуск: cd джерела && python3 проби/skladena_nazva_185.py"""
import collections, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, назва_речі as НР, фід_слот as ФС
оф = feed.читати_yml(feed.каталог_на_диску())[0]
склад = [o for o in оф if o.get("назва_показу_джерело") == "складено"]
іменник = lambda т: (ФС.предмет_назви(str(т or "").lower()) or (None, None))[1]
той_самий = lambda a, b: bool(a and b) and (НР.РУБРИКА_ТИП.get(a) or a) == (НР.РУБРИКА_ТИП.get(b) or b)
суперечать, пояснені = [], collections.Counter()
for o in склад:
    с, п = іменник(o.get("назва")), іменник(o.get("назва_показу"))
    if not (с and п) or с == п or той_самий(с, п):
        пояснені["той самий іменник або синонім"] += bool(с and п and (с == п or той_самий(с, п)))
        continue
    причина = str(o.get("назва_показу_причина") or "")
    якщо = ("речення фіду — іменник у ньому випадковий" if причина.startswith(("речення", "відгук"))
            else "переклад" if причина.startswith("чужа мова") else None)
    (пояснені.__setitem__(якщо, пояснені[якщо] + 1) if якщо else суперечать.append((o["id"], с, п, причина)))
print("ФАКТ · оферів %d · складених назв %d · іменник суперечить сирій назві: %d"
      % (len(оф), len(склад), len(суперечать) + sum(v for k, v in пояснені.items() if k != "той самий іменник або синонім")))
print("ФАКТ · з них пояснено: %s" % {k: v for k, v in пояснені.items() if k != "той самий іменник або синонім"})
print("ФАКТ · НЕПОЯСНЕНИХ суперечностей: %d %s" % (len(суперечать), суперечать[:4]))
без = [o for o in оф if str(o.get("назва_показу_причина") or "").startswith("нема назви речі")]
print("ФАКТ · «нема назви речі» лишилось %d · серед них клог/снікер/мокасін/резинк/лодочк: %d"
      % (len(без), sum(1 for o in без if any(к in str(o.get("назва") or "").lower()
                                             for к in ("клог", "снікер", "мокасін", "резинк", "лодочк")))))
за_ід = {o["id"]: o for o in оф}
for ід in ("ж-04955@sezone.ua", "ж-10677@cooshwear.com", "ж-07619@gepur.com",
           "ж-08707@emmeliedelage.com", "ж-12425@welfare.ua", "ж-04013@morandi.ua"):
    o = за_ід.get(ід) or {}
    print("ФАКТ · %-26s «%s» → «%s» · тип %s"
          % (ід, str(o.get("назва"))[:40], o.get("назва_показу") or "(назва фіду)",
             ФС.тип_речі(o, ФС.слот(o))))
