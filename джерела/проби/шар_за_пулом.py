# -*- coding: utf-8 -*-
"""#324 · друга річ у «верх» поверх топа — шар чи другий верх? Суд доти вирішував словником `_ШАР2` (жакет, кардиган…),
тепер ще й пулом: річ, яку пул тримає у «верхній_шар», — шар. Друкує факт: скільки речей каталогу мають слот «верх» і
«може стати: верхній_шар», але словник їх не ловить; і що суд каже про образ «топ + така річ + низ + взуття» без пулу
і з пулом (блокер «у сім'ї «верх» 2 речі»). Запуск: cd джерела && python3 проби/шар_за_пулом.py"""
import json, os, re, sys
Д = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, Д); os.chdir(Д)
import bridge as B, суд_від_моделі as С, composer as К
вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
СЛОВНИК = re.compile(r"жакет|кардиган|жилет|піджак|блейзер|болеро|кімоно|накидк|пончо|тренч|бомбер", re.I)
шари = [r for r in кат if r.get("слот") == "верх" and "верхній_шар" in (r.get("слоти_альт") or ())]
поза = [r for r in шари if not СЛОВНИК.search("%s %s" % (r.get("тип") or "", r.get("назва") or ""))]
print("ФАКТ · речей «верх» + «може стати: верхній_шар»: %d · зі словником `_ШАР2` не ловиться: %d (напр. %s)" % (
    len(шари), len(поза), "; ".join(str(r.get("назва"))[:40] for r in поза[:3])))
кейп = next((r for r in поза if "кейп" in str(r.get("назва")).lower()), поза[0])
топ = next(r for r in кат if r.get("слот") == "верх" and not r.get("слоти_альт"))
низ = next(r for r in кат if r.get("слот") == "низ"); вз = next(r for r in кат if r.get("слот") == "взуття")
речі = lambda: [К._у_річ(dict(r), r["слот"], None) for r in (топ, кейп, низ, вз)]
пул = {str(кейп["id"]): {"верх", "верхній_шар"}, str(топ["id"]): {"верх"}, str(низ["id"]): {"низ"}, str(вз["id"]): {"взуття"}}
for ім, сп in (("без пулу", None), ("з пулом", пул)):
    бл = [б for б in С.структура_образу(речі(), сп) if "«верх» 2" in str(б)]
    print("ФАКТ · «%s» поверх топа, %s: блокер «у сім'ї «верх» 2 речі» — %s" % (str(кейп.get("назва"))[:40], ім, "є" if бл else "нема"))
