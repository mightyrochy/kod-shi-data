"""Температура нейтралі й R-COL-16 читають запис, невідоме місце не є вердиктом."""
import sys
from unittest.mock import patch
sys.path.insert(0, ".")
import outfit as О, колір_нейтралі as К, colorspace as Ц, палітра_запити as П

def головна():
    """Зіставляє два суди на «так / ні / невідомо» із суперечливим старим near."""
    особа = Ц.features(Ц.hx("#deb295"), Ц.hx("#f1dbaa"), Ц.hx("#759087"))
    for колір, правило in (("#bfbfbf", "K-COL-06-T"), ("#ff0000", "R-COL-16")):
        for слово in ("так", "ні", None):
            річ = dict(id="шарф", слот="шарф", hex=колір, площа=0.1)
            if слово:
                річ["місце_стилістки"] = dict(біля_обличчя=слово, слова="як вдягнено")
            е = О.елементи([річ])[0]
            е["near"] = 0 if слово == "так" else 1
            with patch.object(К._ПН_Т, "нейтраль_якір", wraps=К._ПН_Т.нейтраль_якір) as якір:
                з = (К.температура_нейтралі([е], особа, драп=dict(метал="золото", нейтралі="теплі"), речі=[річ])
                 if правило == "K-COL-06-T" else К.бік_b_біля_обличчя([е], {},
                     _бб=dict(вхід=True, бік=-1, b_очей=-10, довіра=1)))
            print(правило, слово, "→", [(x["сила"], x.get("бракує")) for x in з])
            assert слово != "ні" or not з
            assert слово is not None or (з and all(x["сила"] == "питання" and x["сила_нп"] == 0 for x in з))
            if правило == "K-COL-06-T":
                assert bool(якір.call_count) == (слово == "так")
                assert not якір.call_count or якір.call_args.kwargs["near"] == 1
            else:
                assert слово != "так" or any(x["сила"] != "питання" for x in з)

    спец = dict(слоти={с: dict(L=[10, 90], C=[20, 30]) for с in ("верх", "шарф", "сережки", "взуття")},
                бік_b=dict(вхід=True, бік=1, довіра=1, b_очей=10))
    запити = П.запит_у_фід(спец)
    боки = {р["слот"] for р in запити if "b_бік" in р}
    print("рядки з боком b*:", sorted(боки))
    assert боки == {"сережки"}

if __name__ == "__main__":
    головна()
