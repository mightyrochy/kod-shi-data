# -*- coding: utf-8 -*-
"""Рядок 195: чи зважує текст образу ЇЇ ДЕНЬ (дію, місце, погоду) — на звітах справжньої моделі («Зберегти
всі вердикти»): по сценарію — карток, у скількох текст (руки 1–2: опис і «як носити», 3–4: проза) називає дію,
місце, погоду; світлий низ до підлоги; і те саме для речень «день» образів складання (звіт гілки 195).
Слова-ознаки — грубий свідок, не суд: текст друкується поруч. Запуск: python3 проби/den_obrazu_195.py ЗВІТ.json …"""
import collections, json, re, sys
import feed as Ф
АСПЕКТИ = {"дія": r"прогулян|гуля|собак|\bпес|ход[иь]|крок|танц|рух|сид[іи]|кермо|авто|машин|урок|діт|на ногах|бігат",
           "місце": r"парк|трав|бруків|газон|сход|вулиц|надвор|просто неба|приміщ|офіс|ресторан|зал|клас|сніг|калюж|бруд",
           "погода": r"°|градус|тепл|холод|прохолод|вітер|вітр|дощ|злив|сніг|мороз|спек|сонц|вологи|промок|мокр|слизьк"}
СВІТЛИЙ, ДОВГИЙ = r"біл|молоч|крем|айвор|беж|світл|пудр|пісоч|ваніл|екрю", r"палаццо|максі|maxi|до підлоги|в підлогу"
аспекти = lambda т: {к: bool(re.search(в, (т or "").lower())) for к, в in АСПЕКТИ.items()}
оф = {o["id"]: o for o in Ф.читати_yml("каталог_повний.xml")[0]}
def світлий_довгий(ід):
    """Чи є в складі світлий низ (сукня) до підлоги — за назвою, кольором крамниці й довжиною фіду."""
    for i in ід:
        o = оф.get(i) or {}
        сл, т = Ф.слот(o) if o else None, " ".join(str(o.get(k) or "") for k in ("назва", "колір_назва")).lower()
        if сл in ("низ", "сукня", "комплект") and re.search(СВІТЛИЙ, т) and (re.search(ДОВГИЙ, т) or Ф.довжина_речі(o, сл)[0] == "максі"):
            return True
    return False
лік = collections.defaultdict(collections.Counter)
for шлях in sys.argv[1:]:
    з = json.load(open(шлях, encoding="utf-8"))
    for пр in з.get("прогони") or []:
        пасп = (пр.get("спільне") or {}).get("паспорт") or (з.get("спільне") or {}).get("паспорт") or {}
        for в in пр.get("вердикти") or []:
            рука, сц = str(в.get("рука")), (в.get("паспорт") or пасп).get("подія") or "?"
            т = (в.get("опис") or "") + " " + " ".join(в.get("як_носити") or []) if рука in ("1", "2") else в.get("текст") or ""
            а, к = аспекти(т), лік[(сц, "руки 1–2" if рука in ("1", "2") else "руки 3–4")]
            к["карток"] += 1; к.update(к_ for к_, v in а.items() if v); к["усі три"] += all(а.values())
            к["світлий низ до підлоги"] += світлий_довгий(str(в.get("склад") or "").split("+"))
            print("%s · рука %s · %s · %s" % (сц, рука, " ".join(("%s ✓" if v else "%s ✗") % к_ for к_, v in а.items()), т.strip()[:160]))
            for ви in ((в.get("етапи") or {}).get("виклики") or []):
                for д in ви.get("дні") or []:
                    ад, кд = аспекти(д.get("день")), лік[(сц, "речення «день» образів")]
                    кд["образів"] += 1; кд.update(к_ for к_, v in ад.items() if v); кд["усі три"] += all(ад.values())
                    кд["світлий низ до підлоги"] += світлий_довгий(д.get("ід") or [])
for (сц, хто), к in sorted(лік.items()):
    print("%-40s %-24s %s" % (сц[:40], хто, dict(к)))
