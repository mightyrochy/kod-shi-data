"""Крок 15631 (Е3-сила-правила): множник «свідомо» як `перезважити(z, None, частка=C["свідомий_розрив_частка"])`
проти старого `round(сила_нп × 0.6, 2)` — сітка ваги 0…1 крок 0.01 × п'ять категорій × `блокує`; порівнюється
ефективна вага, мітка підлоги й блокування після `обмежити_вагу`, якою їх читає `вердикт_моделі.py:441`."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import реєстр_правил as R
from реєстр_сила import обмежити_вагу

СТАРИЙ = 0.6   # `СВІДОМИЙ_МНОЖНИК` ДО кроку (`розбір_відповідей.py:1198`)
assert R.C["свідомий_розрив_частка"] == СТАРИЙ, R.C["свідомий_розрив_частка"]
входів = розбіжностей = 0
for с in ("hint", "soft", "default", "strong", "hard"):
    for і in range(101):
        for бл in (False, True):
            z = dict(правило="K-COL-03", сила=с, сила_нп=і / 100, блокує=бл, суть="x", речі=[])
            до = обмежити_вагу([dict(z, сила_нп=round(і / 100 * СТАРИЙ, 2))])[0]
            після = R.перезважити(z, None, частка=R.C["свідомий_розрив_частка"])
            входів += 1
            ключ = lambda d: (d["сила_нп"], bool(d.get("під_підлогою")), bool(d.get("блокує")))
            if ключ(до) != ключ(після):
                розбіжностей += 1
                print("розбіжність", с, і / 100, бл, ключ(до), ключ(після))
print("входів %d, розбіжностей ваги, підлоги й блокування: %d" % (входів, розбіжностей))
sys.exit(1 if розбіжностей else 0)
