# -*- coding: utf-8 -*-
"""НАМІР У `bases.ранг` — виміряно: `python проби/nam_ранг.py`.

ДО: `intent` стояв у сигнатурі, `bridge._основи` передавав його ІМЕНЕМ, а ранг
віддавав conventional і statement ОДНАКОВИЙ ряд — на ґратці 116 основ тіла
стенда збігались і топ-5, і бал першої основи (0.704), і ліміт (12.3 L*).
ПІСЛЯ: під сміливим наміром стеля контрасту біля обличчя ширша на крок Value
(K-PER-00, `зона_світлоти`: «зона ширшає на крок Value з кожного боку»), тож
основи, що перевищували власний контраст особи, перестають каратись і ряд їде
вгору. Проба друкує ліміт, топ-5, бал першої й скільки основ ранг більше не
вважає перевищенням."""
import sys, pathlib, json
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import bridge as B, bases as ОС, palette as П, outfit as O

вх = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
F, T, _зр, _kw = B._збірка(вх)
таб, пор = B._ґратка_основ()
к = O.контраст_особи(F, "uncontrolled")
було = {}
for намір in ("conventional", "statement"):
    вх["намір"] = намір
    р, п = ОС.ранг(F, таб, пор,
                   контраст=dict(value_gap=к.get("value_gap"), рівень=к.get("рівень")),
                   надійність=П.reliability("uncontrolled"), intent=намір)
    поза = [x for x in р if x["перепад"] > п["ліміт_особи"]]
    у_лімі = [x for x in поза if x["перепад"] <= п["ліміт_контрасту"]]
    print("%-13s ліміт %.1f L* (особа %.1f + намір %.1f) · основ %d · бал#1 %.3f"
          % (намір, п["ліміт_контрасту"], п["ліміт_особи"], п["важіль_наміру"],
             len(р), р[0]["бал"]))
    print("   топ-5: " + ", ".join(x["ключ"].split("·")[0] + "/" + x["ключ"].split("·")[2]
                                   for x in р[:5]))
    print("   поза контрастом особи %d основ, із них помилувано наміром %d; "
          "середній бал ряду %.3f" % (len(поза), len(у_лімі),
                                      sum(x["бал"] for x in р) / len(р)))
    було[намір] = (п["ліміт_контрасту"], [x["ключ"] for x in р[:5]],
                   round(sum(x["бал"] for x in р) / len(р), 4))
assert було["conventional"] != було["statement"], "намір не доїхав до рангу"
print("РІЗНИЦЯ Є: ліміт %.1f→%.1f, середній бал %.4f→%.4f, топ-5 %s"
      % (було["conventional"][0], було["statement"][0],
         було["conventional"][2], було["statement"][2],
         "інший" if було["conventional"][1] != було["statement"][1] else "той самий"))
