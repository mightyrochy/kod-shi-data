# -*- coding: utf-8 -*-
"""Проба (рядок 1480): КОЛІР ПРИКРАСИ З МЕТАЛОМ — З КАДРУ ЧИ ЗІ СЛОВА МЕТАЛУ. На всьому каталозі:
скільки прикрас із металом мають виміряний колір поза вікнами металу (`колір_вставки`: емаль,
камінь), скільки з них «несуть колір» до і після (`palettes._несе_колір` без поля / з полем), і
скільки прикрас знають колір лише словом металу (`_колір_невідомий`). Друкує факт, моделі не кличе.
Запуск: python3 джерела/проби/прикраси_вставка_1480.py"""
import collections, os, sys                                                   # noqa: E401
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import фід_каталог as ФК, palettes as ПЛ                                      # noqa: E401,E402
записи = ФК._прочитати_каталог(ФК.каталог_на_диску(), ліміт_фото=0)["каталог"]
c = collections.Counter()
for r in записи:
    if not r.get("метал") or r.get("слот") not in ПЛ.СЛОТИ_МЕТАЛУ:
        continue
    c["з_металом"] += 1
    вст = r.get("колір_вставки")
    c["кадр_виміряно"] += вст is not None
    c["невідомий"] += ПЛ._колір_невідомий(r) and not ПЛ._несе_колір(r)
    if not вст:
        continue
    c["вставка"] += 1
    c["вставка_хроматична"] += bool(ПЛ._хроматична_вставка(r))
    c["несе_до"] += bool(ПЛ._несе_колір({к: v for к, v in r.items() if к != "колір_вставки"}))
    c["несе_після"] += bool(ПЛ._несе_колір(r))
    б, в = ПЛ._хроматична(ПЛ._lab_повної(r)), ПЛ._хроматична_вставка(r)
    c["дві_сім_ї"] += bool(б and в and б[0] != в[0])      # база й вставка — різні сім'ї (K-COL-03)
print("прикрас із металом %d · кластери кадру виміряно %d · колір лише словом металу (нейтраль не доведено) %d"
      % (c["з_металом"], c["кадр_виміряно"], c["невідомий"]))
print("вимір поза вікнами металу (емаль, камінь) %d, з них хроматичний %d"
      % (c["вставка"], c["вставка_хроматична"]))
print("із %d «несуть колір»: до %d → після %d; база й вставка — дві кольорові сім'ї: %d"
      % (c["вставка"], c["несе_до"], c["несе_після"], c["дві_сім_ї"]))
р = next(r for r in записи if r["id"].startswith("ж-11806@"))
print("ж-11806 «%s»: колір_вставки %s · колір невідомий %s · несе колір %s"
      % (р["назва"], р.get("колір_вставки"), ПЛ._колір_невідомий(р), ПЛ._несе_колір(р)))
