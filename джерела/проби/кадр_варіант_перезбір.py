"""Перезбирає копію повного каталогу з Shopify-знімків; перевіряє сталість id при повторі.
Запуск: python джерела/проби/кадр_варіант_перезбір.py <тека знімків>. Продуктових файлів не пише."""
import gzip, json, sys
from pathlib import Path
КОРІНЬ = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРІНЬ / "zhnyvarka"))
import жниварка as ж
import shopify_варіанти as ш
import складальник as с


def main():
    """Застосовує той самий знімок двічі без втрати старих або додавання повторних id."""
    _, записи = с.читати_записи()
    знімки = {ф.name[:-8]: json.loads(gzip.decompress(ф.read_bytes())) for ф in Path(sys.argv[1]).glob("*.json.gz")}
    assert знімки and all(знімки.values()), "Немає повних знімків"
    збагачення = json.loads(gzip.decompress((КОРІНЬ / "джерела/каталог_збагачення.json.gz").read_bytes()))
    кадри = json.loads(gzip.decompress((КОРІНЬ / "джерела/каталог_кадри.json.gz").read_bytes()))
    магазини = {м["домен"]: м for м in ж.читати_магазини(str(КОРІНЬ / "zhnyvarka/магазини.tsv"))}
    нові, відповідність, зб, км, звіт, черга = ш.перебрати(
        записи, знімки, ш.читати_рецепти(), збагачення, кадри, "2026-11-02", ж=ж, магазини=магазини)
    повтор = ш.перебрати(нові, знімки, ш.читати_рецепти(), зб, км, "2026-11-02", ж=ж, магазини=магазини)
    ід_до, ід_після = {з["ід"] for з in записи}, {з["ід"] for з in нові}
    assert len(ід_після) == len(нові) and ід_до <= ід_після
    assert ід_після == {з["ід"] for з in повтор[0]} and len(повтор[0]) == len(нові)
    assert нові == повтор[0], [(а["ід"], {к: (а.get(к), б.get(к)) for к in а.keys() | б.keys() if а.get(к) != б.get(к)}) for а, б in zip(нові, повтор[0]) if а != б][:2]
    print(json.dumps(dict(записів_ДО=len(записи), записів_ПІСЛЯ=len(нові), повтор=len(повтор[0]),
                          втрачено_ід=len(ід_до - ід_після), повторів_ід=len(нові) - len(ід_після),
                          відповідність=len(відповідність), збагачень=len(зб), черга=len(черга), крамниці=звіт), ensure_ascii=False))


if __name__ == "__main__":
    main()
