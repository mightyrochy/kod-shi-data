"""K-SIL-05 (візуальна вага й опора) — «БЕЗ ВХОДУ», і це сказано вголос:
`python3 проби/sil_K-SIL-05.py`.

Правило просить ОДНОГО порівняння: маса низу проти маси взуття. Маси не несе
жодне поле каталогу — ні ваги виробу, ні щільності тканини, ні маси підошви; є
`каблук_см` (1 136 пар) і `підошва` (379), тобто висота й матеріал, не маса. Сам
корпус пише те саме дослівно: «no feed carries either, so the rule has no input
today», а прогін 3 (06.09) закрив правило для досліджень — названого джерела в
нього немає, і напрям ваги може прийти лише з ВИМІРУ, не з читання.
ЩО ДРУКУЄ ПРОБА: перевірка на каталозі, що жодного поля маси справді нема, і
запис у реєстрі обмежень із названим полем. Емітента нема навмисно."""
import sys, pathlib, json, collections
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import feed as Ф, bridge as B, status as СТ, accessory as АК

вх = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml"); вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
ПОЛЯ_МАСИ = ("вага", "вага_г", "маса", "маса_г", "щільність", "щільність_гм2",
             "грамаж", "маса_підошви")
є = collections.Counter()
for c in кат:
    for п in ПОЛЯ_МАСИ:
        if c.get(п) not in (None, "", [], {}):
            є[п] += 1
print("речей у каталозі пакета:", len(кат))
print("полів маси знайдено:", dict(є) or "жодного — 0 із %d речей" % len(кат))
є_каблук = sum(1 for c in кат if c.get("каблук_см") is not None)
є_підошва = sum(1 for c in кат if c.get("підошва"))
print("що замість маси Є: каблук_см %d · підошва %d — це висота й матеріал, не маса"
      % (є_каблук, є_підошва))
print("маса взуття в коді рахується з ТИПУ (категорія, не вимір):",
      sorted(АК.МАСА_ВЗУТТЯ)[:5] if hasattr(АК, "МАСА_ВЗУТТЯ") else "accessory.маса_взуття")
обм = next((з for з in СТ.ОБМЕЖЕННЯ if з["id"] == "маса_речі"), None)
print("у реєстрі обмежень:", (обм or {}).get("наслідок", "НЕМА")[:96])
assert not є and обм, (є, bool(обм))
