# -*- coding: utf-8 -*-
"""Проба (рядок 2240): K-CRA-04 × тихі джерела. Підлога K-INT-04 рахує i1/i2 (`тихі_джерела`) за
будь-якого наміру, а крок редагування мусить міряти інтерес тією самою лінійкою — інакше річ, що
єдина дає тихе джерело, виходить «зайвою». 1) Образ рядка: сукня + вовняний шарф + взуття, усе
нейтральне. 2) Усі різні образи рук 1–2 збережених прогонів (`аудит/перевірки/**/вердикти*.gz`, як
`тихі_1850.py`): скільки разів K-CRA-04 радить зняти річ, без якої в образі 0 джерел (ні гучних,
ні тихих), хоч з нею ≥1. Червоне — таких > 0. Моделі не кличе. Запуск: python3 джерела/проби/тихі_ред_2240.py"""
import collections, glob, gzip, os, re, sys                                   # noqa: E401
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ)
import фід_каталог as ФК, композитор_річ as КР, outfit as O                    # noqa: E401,E402
import суд_інтерес as СІ                                                      # noqa: E402
дж = lambda E: len(СІ.джерела_інтересу(E) + СІ.тихі_джерела(E))              # noqa: E731
def голі(E):
    """Зайві K-CRA-04, без яких образ лишається без жодного джерела."""
    з, _, _ = СІ.крок_редагування(E)
    к = lambda x: x.get("річ") or x.get("id")                                  # noqa: E731
    return [z["речі"][0] for z in з if дж(E) >= 1 and not дж([x for x in E if к(x) != z["речі"][0]])]
н = dict(lab=(45.0, 0.5, 1.0), L=45.0, C=1.1, сім_я="сірий", нейтраль=True)
E = [dict(н, річ="сукня", слот="сукня", площа=0.55, текстура="smooth-matte"),
     dict(н, річ="шарф", слот="шарф", площа=0.08, волокно="вовна"),
     dict(н, річ="взуття", слот="взуття", площа=0.05, текстура="smooth-matte")]
з, заб, база = СІ.крок_редагування(E)
print("образ рядка: зайві=%s заборонені=%s база інтерес=%d; тихих %d" % (
    [z["речі"][0] for z in з], [z["речі"][0] for z in заб], база["інтерес"], len(СІ.тихі_джерела(E))))
за_ід = {r["id"]: r for r in ФК._прочитати_каталог(ФК.каталог_на_диску(), ліміт_фото=0)["каталог"]}
набори = {}
for ф in sorted(glob.glob(os.path.join(ТУТ, "..", "аудит", "перевірки", "**", "вердикти*.gz"), recursive=True)):
    for м in re.finditer(r'\\?"ід\\?": ?\[([^\]]*)\]', gzip.open(ф).read().decode()):
        ід = tuple(sorted(set(re.findall(r'ж-[^"\\,]+', м.group(1)))))
        if len(ід) >= 2 and all(і in за_ід for і in ід):
            набори.setdefault(ід, "похорон" in ф)
лік, слоти = collections.Counter(), collections.Counter()
for ід, траур in набори.items():
    E = O.елементи([КР._у_річ(за_ід[і], за_ід[і]["слот"], None) for і in ід])
    г = голі(E)
    лік[("траур" if траур else "решта", "образів")] += 1
    лік[("траур" if траур else "решта", "зняти єдине джерело")] += bool(г)
    for р in г:
        слоти[next(e.get("слот") for e in E if (e.get("річ") or e.get("id")) == р)] += 1
print("образів рук 1–2: %s" % dict(лік))
print("слоти «зайвих» єдиних джерел: %s" % dict(слоти))
x = sum(v for (_, k), v in лік.items() if k != "образів")
print("K-CRA-04 знімає єдине джерело: %d — %s" % (x, "ЧЕРВОНЕ" if x else "зелене"))
