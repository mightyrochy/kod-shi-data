"""Частина кв1 (кадр_варіант_кадр_колір): скільки кадрів галереї-виміру офер бере свідком кольору «своїм» без доказу власника.
ДО (`main`) — кожен кадр виміру; ПІСЛЯ — лише з доказом свого варіанта (`фід_кадр_колір.кадр_варіант`), решта «невідомо».
Запуск: python3 -W ignore джерела/проби/кадр_варіант_кв1_свої.py"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import feed, фід_кадр_колір as К
оф = feed.читати_yml(feed.каталог_на_диску())[0]
кадри = К.читати_кадри()
всього = свої = 0
for о in оф:
    if "власник_кадру" not in (о.get("параметри") or {}):
        continue
    for в in кадри.get(о.get("id")) or ():
        всього += 1
        свої += К.кадр_варіанта(о, в) if hasattr(К, "кадр_варіанта") else True
print("вимірів кадрів в офер з параметром власника: %d · свідком як «свій» (ДО=усі): %d · «невідомо»: %d" % (всього, свої, всього - свої))
