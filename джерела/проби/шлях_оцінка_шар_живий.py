"""Ділянка 8: ЧИ СПРАВДІ ХІД ІДЕ ШАРОМ МОВИ у власника. Карта ділянки стоїть на тому, що
`МОДЕЛЬ_МОВИ_П` вмикається сам (показ.html:6444) — тут це звіряється з ЙОГО ВЛАСНИМИ прогонами:
записи `мова_шару` у файлах вердиктів 25.09 (поле per-вердикт, не `спільне`, тож знахідка
ділянки 2/8 про стан на момент вивантаження його не стосується).
Запуск із `джерела`: python3 проби/шлях_оцінка_шар_живий.py"""
import sys, json, re, glob; sys.path.insert(0, '.')
T = open('показ.html', encoding='utf-8').read()
ряд = lambda взір: T[:re.search(взір, T).start()].count('\n') + 1
print('показ.html:%d — %s' % (ряд(r'return БЕЗ_ШАРУ_МОВИ_П\.test'),
                              re.search(r'return БЕЗ_ШАРУ_МОВИ_П\.test.*', T).group(0).strip()))
print('  → без явного «нема» шар бере МОДЕЛЬ_П, тобто модель продукту')
for шлях in sorted(glob.glob('../аудит/тести/власник_2026-09-25/verdykty-*.json')):
    д = json.load(open(шлях, encoding='utf-8'))
    print('%s — прогонів %d' % (шлях.rsplit('/', 1)[1], len(д['прогони'])))
    for пр in д['прогони']:
        збірка = (пр['спільне'].get('збірка') or '')[:16]
        записи = [з for в in пр['вердикти'] for з in (в.get('мова_шару') or []) if isinstance(з, dict)]
        моделі = sorted({str(з.get('модель')) for з in записи})
        збої = [з for з in записи if з.get('причина')]
        print('  %s · вердиктів %d · записів мова_шару %d · моделі шару: %s · збоїв %d'
              % (збірка, len(пр['вердикти']), len(записи), ', '.join(моделі) or '—', len(збої)))
print('→ на збірці 25.09 (та сама, що й на записі 26.09 — «модулів 138») шар мови ПРАЦЮВАВ')
print('  живою моделлю продукту; на збірках 22.09 і 24.09 записів нема (шар злито #317 25.09).')
print('  Отже крок 2, 6 і 8 карти ділянки — справжній шлях власника, а не гілка main.')
