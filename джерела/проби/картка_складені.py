"""Зміни складених фактів розмовою й коментарем зберігаються на наступному ході."""
import copy
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import мовний_шар as М
import картка_запиту as К
import паспорт_поля as П


def main():
    """Виміряти втрати, повторне зняття та спільні посилання старого й нового паспортів."""
    хід = lambda в, п: М.паспорт_з_шару(в, {}, паспорт_досі=п,
                                       слова_ходу=["сукня кросівки без принта без каблука"])['паспорт']
    подія = {"wants": [{"item_type": "sneakers", "quote": "кросівки"}],
             "vetoes": [{"pattern": "print_generic", "quote": "без принта"}]}
    втрат = 0
    for джерело in (П.ТЛУМАЧЕННЯ, П.ЇЇ, П.РУКА):
        for шлях in ("коментар", "розмова"):
            п = {}
            К.записати(п, "бажання", ["сукня"], джерело, "сукня")
            К.записати(п, "вето", {"типи": ["каблук"], "принти": []}, джерело, "без каблука")
            було = copy.deepcopy(п)
            з = М.паспорт_з_коментаря(подія, п)["паспорт"] if шлях == "коментар" else хід(подія, п)
            далі = хід({}, з)
            знято = хід({"retract": подія["wants"] + подія["vetoes"]}, далі)
            гаразд = (далі["бажання"] == ["сукня", "кросівки"] and
                       далі["вето"].get("принти") == ["принт"] and знято["бажання"] == ["сукня"] and
                       not знято["вето"].get("принти") and not знято.get("вето_тверде", {}).get("принти") and
                       len(знято.get("бажання_коди", [])) == 0 and п == було)
            втрат += not гаразд
            print(json.dumps(dict(шлях=шлях, джерело=джерело, бажання=далі["бажання"],
                                  принти=далі["вето"].get("принти"), знято=знято["бажання"], гаразд=гаразд), ensure_ascii=False))
    print("порушень складених фактів:", втрат)
    return int(bool(втрат))


if __name__ == "__main__":
    sys.exit(main())
