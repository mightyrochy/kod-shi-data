# -*- coding: utf-8 -*-
"""КОЛІР-КОДУВАННЯ (рядок 2691): речі `каталог_повний` з кольором-ВІКНОМ, у яких поруч лежить вимір жнив v2
(`каталог_збагачення.json.gz`, hex маски). Чому код вимір не взяв і чи він придатний: (а) причина (`колір_спір`);
(б) згода свідків (`впевненість` жнив: маска .35, слово моделі .25, крамниця .20, друге фото .20; поріг
`фід_збагачення.ЗБАГАЧЕННЯ_ЗГОДА`); (в) hex узгоджений зі словом моделі (`колір_збагачення` «hex…») чи ні;
(г) вимір лежить у вікні вжитку слова крамниці (`verify.перевірити`); (д) те саме для гучних (C* вікна ≥40) і чи
вимір теж гучний — центр вікна слова сам робить річ «гучною».
Запуск із джерела/: python3 проби/колір_де_губиться_вимір.py"""
import json, gzip, sys, collections as K
sys.path.insert(0, "."); import bridge as B, стенд_знімок as СЗ, colorspace as cs, колір_річ as КР, verify as V
import фід_збагачення as ФЗ
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
B.виклик("запити", json.dumps(dict(вх, сценарій=СЗ.СЦЕНАРІЇ["офіс·18°C"], випадок="офіс"), ensure_ascii=False))
кат, зб = B.каталог_останнього_пакета(), json.load(gzip.open("каталог_збагачення.json.gz"))
Л = K.Counter()
for r in кат:
    нв, з = КР.не_вимір(r), зб.get(r["id"]) or {}
    if not нв or нв["свідок"] != "слово крамниці" or з.get("версія") != 2 or not (з.get("колір_основний") or {}).get("hex"):
        continue
    сп = r.get("колір_спір") or {}
    у = float(з.get("впевненість") or 0)
    слово, lab, за = ФЗ.колір_збагачення(з)
    сирий = ФЗ._lab_з_hex(з["колір_основний"]["hex"])
    у_вікні = V.перевірити(сирий, ім=нв["слово"])["вердикт"] == "прийнято" if нв["слово"] in V.ЛЕКСИКОН else None
    гучна = cs.lch(tuple(r["lab"]))[1] >= 40
    Л["(а) причина: " + (сп.get("чому") or "без спору (чужий кадр / інше)")] += 1
    Л["(б) згода свідків: %s" % ("1.0" if у >= .995 else "0.9–0.99" if у >= .9 else "0.8–0.89" if у >= .8 else "0.6–0.79" if у >= .6 else "<0.6")] += 1
    Л["(в) hex узгоджений зі словом моделі: %s" % за.startswith("hex")] += 1
    Л["(г) сирий вимір у вікні вжитку слова крамниці: %s" % у_вікні] += 1
    if гучна:
        Л["(д) гучних: усього"] += 1
        Л["(д) гучних: вимір у вікні слова крамниці і та сама сім'я: %s" % bool(у_вікні and сп.get("чому") == "згода свідків нижча за поріг")] += 1
        Л["(д) гучних: згода ≥0.8: %s" % (у >= .8)] += 1
        Л["(д) гучних: вимір v2 теж гучний (C*≥40): %s" % (cs.lch(tuple(сирий))[1] >= 40)] += 1
print("вікон «слово крамниці» з виміром v2 поруч:", sum(v for k, v in Л.items() if k.startswith("(а)")), "· поріг згоди", ФЗ.ЗБАГАЧЕННЯ_ЗГОДА)
for к, n in sorted(Л.items()): print("  %-72s %5d" % (к, n))
