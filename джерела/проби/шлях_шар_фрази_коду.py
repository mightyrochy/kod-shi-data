# -*- coding: utf-8 -*-
"""М-1, кошик В (аудит/ПРОДУКТ.md п.12): ФРАЗИ, ЯКІ КОД ПИШЕ ЛЮДСЬКОЮ МОВОЮ НА ШЛЯХУ РОЗМОВИ З ШАРОМ.
Лічить кириличні слова (≥3 літер), які пише сам код: (1) опис її дня для функціональних
моделей (`сценарій.день_*`) на прогулянці й у театрі; (2) запасна репліка з ендпойнта `мова`;
(3) рядкові літерали в `розмоваШаромП` / `реплікоюП` показу (без коментарів), ОКРЕМО
фрази коду (літерал із пробілом — кошик В, мусить бути 0) і ід внутрішньої мови (одне слово:
маршрут моста, режим екрана, `де`, `напрям`, `питання_до` — кошик А, лишаються); (4) словники
фраз у `сценарій.py`. Та сама проба на main і на гілці. Запуск із `джерела`:
python3 проби/шлях_шар_фрази_коду.py"""
import sys, os, re, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import сценарій as СЦ, мовний_шар as МШ
слова = lambda т: re.findall(r"[а-яіїєґʼ']{3,}", json.dumps(т, ensure_ascii=False).lower())
день = getattr(СЦ, "день_кодами", None) or СЦ.день_словами
разом = 0
for сц in ({"активність": "прогулянка", "рух": "багато ходити", "місце": "парк", "формат": "просто неба",
            "поверхня": "трава", "тривалість_год": 2, "темп_c": 18, "опади": "ні", "вітер": 7, "година": 11},
           {"місце": "театр", "формат": "приміщення", "темп_c": -8, "опади": "сніг", "година": 18, "тривалість_год": 4}):
    д = день(сц)
    разом += len(слова(д))
    print("день моделям (%s): %s" % (день.__name__, json.dumps(д, ensure_ascii=False)[:190]))
р = json.loads(МШ.мова({"репліка": {"recorded": {"occasion": "date"}, "required": ["occasion"],
                                     "advice_topics": ["makeup"]}, "випадок_людині": "Побачення"}))
print("ендпойнт `мова` на репліку дає запасний текст коду: %s" % json.dumps(р.get("запасний"), ensure_ascii=False)[:120])
разом += len(слова(р.get("запасний") or ""))
T = open("показ.html", encoding="utf-8").read()
# ФРАЗИ проти ІД (М-3): літерал із пробілом — речення, яке пише сам код (кошик В, прибрати);
# літерал з одного слова — ід внутрішньої мови (кошик А: маршрут моста, режим екрана, `де`,
# `напрям`, `питання_до`), який лишається. Лічаться обидва, ПІДСУМОК — сума, як доти.
фраз = ід = 0
for ім in ("розмоваШаромП", "реплікоюП"):
    тіло = re.sub(r"/\*.*?\*/|//[^\n]*", "", re.search(r"async function %s\(.*?\n\}\n" % ім, T, re.S).group(0), flags=re.S)
    літ = [л for л in re.findall(r"'([^'\n]*)'", тіло) if слова(л)]
    ф = [л for л in літ if " " in л.strip()]
    і = [л for л in літ if " " not in л.strip()]
    фраз += sum(len(слова(л)) for л in ф); ід += sum(len(слова(л)) for л in і)
    разом += sum(len(слова(л)) for л in літ)
    print("%s: фраз коду %d (%s); ід внутрішньої мови %d (%s)"
          % (ім, len(ф), " | ".join(ф)[:160] or "—", len(і), " | ".join(і)[:160] or "—"))
print("СЛІВ У ФРАЗАХ КОДУ (кошик В, мусить бути 0): %d; слів в ід (кошик А, лишаються): %d" % (фраз, ід))
словники = [ім for ім in ("ДІЯ_СЛОВАМИ", "ФОРМАТ_СЛОВАМИ", "ОПАДИ_СЛОВАМИ") if hasattr(СЦ, ім)]
разом += sum(len(слова(getattr(СЦ, ім))) for ім in словники)
print("словники фраз у сценарій.py: %s" % (", ".join(словники) or "—"))
print("ПІДСУМОК: кириличних слів, які код пише на шляху розмови з шаром: %d" % разом)
