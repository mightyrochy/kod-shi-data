# -*- coding: utf-8 -*-
"""Розбір шляху 7/8: найвпливовіший словник слів продукту — `фід_слот.СЛОТ_КЛЮЧІ`
(категорія+назва крамниці → слот, читає слово, не ідентифікатор) — на скількох
речах РЕАЛЬНОГО каталогу він фактично вирішує. Не тлумачить, лише лічить.
Прогін: python3 проби/шлях_слова_слот_каталог.py"""
import os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import фід_каталог as ФК, фід_слот as ФС

кат = ФК._прочитати_каталог(ФК.каталог_на_диску("каталог_повний.xml"), ліміт_фото=0)["каталог"]
слот_словником = [c for c in кат if ФС.слот(c) is not None]
має_тип = [c for c in кат if c.get("тип")]
print("речей у каталозі: %d" % len(кат))
print("`слот()` (слова категорії+назви, СЛОТ_КЛЮЧІ) віддає слот: %d (%.0f %%)"
      % (len(слот_словником), 100 * len(слот_словником) / len(кат)))
print("уже має поле `тип` (готовий ідентифікатор роду речі): %d (%.0f %%)"
      % (len(має_тип), 100 * len(має_тип) / len(кат)))
print("без слота взагалі (не одяг/чужий канал/не розпізнано): %d"
      % (len(кат) - len(слот_словником)))
