# -*- coding: utf-8 -*-
# Реєстр проблем бази одягу, напрям В, клас «опис». ФАКТ на чистому каталозі: (1) скільки
# оферів без опису і з куцим (< 40 знаків); (2) шаблонні описи — однаковий початок (120 знаків)
# у ≥ 10 оферів: умови повернення, таблиці розмірів, блоки сторінки замість опису речі;
# (3) HTML-сутності й теги, що доїхали в текст; (4) опис російською (за літерами ы/э/ъ/ё і
# частими російськими словами); (5) блок «схожі/рекомендовані» в описі (рядок 3871).
import os, re, sys, collections as C
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed
оф = feed.читати_yml(sys.argv[1] if len(sys.argv) > 1 else feed.каталог_на_диску())[0]
оп = [str(o.get("опис") or "") for o in оф]
print("оферів %d · без опису %d · куцих (< 40 знаків) %d"
      % (len(оф), sum(1 for x in оп if not x.strip()), sum(1 for x in оп if 0 < len(x.strip()) < 40)))
поч = C.Counter(x[:120] for x in оп if len(x) >= 40)
шабл = [(k, v) for k, v in поч.items() if v >= 10]
print("шаблонних початків %d — оферів у них %d; найбільші:" % (len(шабл), sum(v for _, v in шабл)))
for k, v in sorted(шабл, key=lambda x: -x[1])[:5]:
    print("  %4d × «%s…»" % (v, k[:70]))
print("HTML-сутність чи тег у описі: %d" % sum(1 for x in оп if re.search(r"&#?\w+;|</?[a-z]+[ />]", x)))
РОС = re.compile(r"[ыэъё]|\b(платье|юбка|брюки|женск\w*|рубашка|размер\w*|ткань)\b", re.I)
рос = C.Counter(o["магазин"] for o, x in zip(оф, оп) if РОС.search(x[:400]))
print("опис російською: %d · крамниці %s" % (sum(рос.values()), dict(рос.most_common(5))))
СХОЖІ = re.compile(r"схожі товари|вам також|з цим товаром|рекомендуємо|ви переглядали|дивіться також", re.I)
print("блок «схожі/рекомендовані» в описі: %d" % sum(1 for x in оп if СХОЖІ.search(x)))
СХОЖІ_БЕЗ = re.compile(r"схожі товари|вам також|з цим товаром|ви переглядали|дивіться також", re.I)   # «рекомендуємо» — слово самого опису (рядок 6804)
print("  з них без слова «рекомендуємо» (блок сторінки): %d" % sum(1 for x in оп if СХОЖІ_БЕЗ.search(x)))
