# -*- coding: utf-8 -*-
"""Н1: довіра до відтінку очей із портрета. `міст_вхід._features` тепер каже `cs.features`, звідки
взяті кольори (`source`, типове `uncontrolled`), тож `F["_meta"]["from_photo"]` уперше правдивий, і
`bases._температура_людини` бере надійність тону 0.35 (K-PC-05) замість повної 1.0. Друкує на профілі
стенда (очі сіро-зелені / карі / світло-сині): впевненість осі тону ДО і ПІСЛЯ, скільки з 8 КОЛЬОРОВИХ
основ рангу змінилось (нейтралі тону не мають — на них вісь мовчить), чи лишився рядок «температура»
в поясненні чипа. З теки `джерела`: `python3 проби/bas_ochi_foto_н1.py`."""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge as B, colorspace as cs
вх = json.load(open("стенд_вх.json", encoding="utf-8"))


def ранг(очі, як_доти):
    """Вісімка, бали й пояснення для тих самих рис; `як_доти` — брехня `from_photo=False`."""
    F = B._features(dict(вх, очі=очі))[0]
    if як_доти:
        F["_meta"] = dict(F["_meta"], from_photo=False)
    о = B._основи(F)
    усі = о["рекомендовані"] + о["інші"]
    return ([x["ключ"] for x in усі if x["сім_я"] != "нейтраль"][:8],
            {x["ключ"]: x["бал"] for x in усі}, о["пояснення"]["температура"],
            sum(1 for x in усі if "температура" in x["чому"]))

print("надійність тону з фото (uncontrolled) = %.2f, поріг висновку %.1f"
      % (cs.reliability("uncontrolled")["hue"], cs.MIN_TO_EMIT))
for очі in ("#759087", "#5a3a1e", "#7fa8d8"):
    в8, б0, т0, ч0 = ранг(очі, True)
    п8, б1, т1, ч1 = ранг(очі, False)
    print("== очі %s · позиція %+.2f (та сама) · впевненість %.2f → %.2f · джерело: %s"
          % (очі, т1["позиція"], т0["впевненість"], т1["впевненість"], т1["джерело"]))
    print("   кольорові 8 до:    " + " | ".join(в8))
    print("   кольорові 8 після: " + " | ".join(п8))
    print("   змінилось позицій у вісімці: %d/8 · у ранзі балів: %d/%d · max|Δбал| %.3f · "
          "чипів із рядком «температура»: %d → %d"
          % (sum(1 for a, b in zip(в8, п8) if a != b), sum(1 for k in б0 if б0[k] != б1[k]),
             len(б0), max(abs(б0[k] - б1[k]) for k in б0), ч0, ч1))
    assert т0["позиція"] == т1["позиція"], "знак і сила з b* очей не мали змінитись"
    assert т1["впевненість"] <= т0["впевненість"], "довіра з фото не може зрости"
print("bas_ochi_foto_н1: зелено")
