# -*- coding: utf-8 -*-
"""Розбір 3/8: на що показує «повтор речі між руками» (K-VAR-01 прогону).

Скарга власника: той самий кардиган sunwin-store ж-08489 (2 380 ₴) стоїть у
картках рук 1 і 2 одного прогону (знімки 1–2). Проба друкує на прогонах власника:
склад образу кожної руки, знахідки K-VAR-01 У ФАЙЛІ (те, що правило сказало тоді)
і поруч — що воно каже ЗАРАЗ на тих самих картках (`повнота_образу.повтор_прогону`).
Вада: правило називає ЇЇ закріплену річ, яку код сам ставить у кожен образ, і не
бачить справжнього дубля.
Прогін: cd джерела && python3 проби/шлях_пул_дубль_між_руками.py
"""
import collections, json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import повнота_образу as ПО
ФАЙЛ = os.path.join(os.path.dirname(ТУТ), "аудит", "тести", "власник_2026-09-25",
                    "verdykty-0phxvk-2026-09-25-2012.json")
for пр in json.load(open(ФАЙЛ, encoding="utf-8"))["прогони"]:
    сп = пр["спільне"]
    print("прогін розклад %s (%s), вердиктів у файлі %d — руки %s"
          % (сп.get("розклад"), сп.get("дата"), len(пр["вердикти"]),
             [в.get("рука") for в in пр["вердикти"]]))
    скільки, реєстр = collections.Counter(), {}
    назви = {r.get("ід") or r.get("id"): r.get("назва")
             for r in (сп.get("паспорт") or {}).get("речі_з_фото") or []}
    for в in пр["вердикти"]:
        речі = [x for x in str(в.get("склад") or "").split("+") if x]
        скільки.update(речі)
        print("   рука %s: %d речей — %s" % (в.get("рука"), len(речі), ", ".join(речі)))
        for з in (в.get("знахідки_коду") or []):
            if з.get("правило") == "K-VAR-01":
                print("      K-VAR-01 У ФАЙЛІ на %s: %s" % (з.get("речі"), str(з.get("суть"))[:96]))
        # ТЕ САМЕ ПРАВИЛО ЗАРАЗ, на тих самих картках і в тому самому порядку рук
        зн = ПО.повтор_прогону(реєстр, str(в.get("рука")),
                               [dict(id=і, назва=назви.get(і, і)) for і in речі])
        if зн:
            print("      K-VAR-01 ЗАРАЗ на %s: %s" % (зн.get("речі"), str(зн.get("суть"))[:96]))
    дублі = {i: n for i, n in скільки.items() if n > 1}
    print("   речі, що стоять у ДВОХ і більше руках цього прогону: %s"
          % (дублі or "— (у файлі менше двох рук з каталогом)"))
