"""КОЛІР-Р4-2в (рядок 2950, частина «добір»): склад пулу руки 1 за свідком кольору на трьох сценах стенда.
Пул — вхід семплера (`семплер.вибрати`, перший виклик сцени), свідок — `колір_річ.не_вимір` запису каталогу
(«вимір» — поля нема). Друкує розмір пулу, частку кожного свідка і скільки речей кожного свідка добір судив
вікном (`колір_річ.вікно_речі`; ДО — поле `вікно`). ДО/ПІСЛЯ — той самий запуск на двох головах; за `-р`
друкує ще id пулу (для порівняння складу: `diff`). Запуск із джерела/: python3 проби/колір_пул_свідки.py [-р]"""
import sys, json, collections as K; sys.path.insert(0, ".")
import bridge as B, стенд_знімок as СЗ, семплер as С, композитор_слоти as КС, колір_річ as КР
ВІКНО = getattr(КР, "вікно_речі", lambda r: r.get("вікно"))
СВ, ПУЛ, _в, _к = {}, [], С.вибрати, КС._кандидати_на_слот
def _вибрати(к, *a, **kw):
    if not ПУЛ: ПУЛ.append([(с, r.get("id")) for с, v in к.items() for r in v])
    return _в(к, *a, **kw)
def _кандидати(речі, *a, **kw):
    for r in речі: СВ[r.get("id")] = ((КР.не_вимір(r) or {}).get("свідок") or "вимір", bool(ВІКНО(r)))
    return _к(речі, *a, **kw)
С.вибрати, КС._кандидати_на_слот = _вибрати, _кандидати
вх0 = json.load(open("стенд_вх.json", encoding="utf-8"))
for н in ("офіс·18°C", "дощ·ресторан·вечір", "весілля·гість"):
    ПУЛ.clear()
    B.виклик("запити", json.dumps(dict(вх0, сценарій=dict(СЗ.СЦЕНАРІЇ[н]), випадок=н), ensure_ascii=False))
    п = ПУЛ[0] if ПУЛ else []
    св = K.Counter(СВ.get(i, ("?", False))[0] for _, i in п)
    вік = K.Counter(СВ[i][0] for _, i in п if СВ.get(i, ("?", False))[1])
    print("%-20s пул %4d | свідок: %s | вікном: %s" % (н, len(п), dict(св.most_common()), dict(вік.most_common())))
    if "-р" in sys.argv:
        for с, i in sorted(п): print("   ", с, i)
