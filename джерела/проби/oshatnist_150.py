# Рядок 150: `формальність_фото` писали, але не читав ніхто — і на весілля їхала
# полотняна сумка, а в офіс сукня-тістечко. Скільки речей пулу правило знімає й
# переставляє на восьми сценах, і скільки лишається далеких від нагоди на 3+.
import sys, os, collections
ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(ТУТ, ".."))
import feed, фід_каталог as ФК, композитор_слоти as КС

СЦЕНИ = {"офіс·18°C": (5, 6), "спека·парк": (2, 3), "дощ·ресторан·вечір": (7, 9),
         "весілля·гість": (7, 9), "весілля·вечір·19:00": (7, 9), "офіс·вечір·код": (6, 8),
         "весілля 17:00 (рядок 150)": (7, 9), "переліт +24 (рядок 150)": (2, 4)}
СЛОТИ = ("сукня", "верх", "низ", "взуття", "сумка", "верхній_шар")
к = ФК.прогін(feed.каталог_на_диску("каталог_повний.xml"), [], кеш="/tmp/_кш_ош.json",
              ліміт_фото=0)["каталог"]
за_слотом = {с: [r for r in к if r["слот"] == с] for с in СЛОТИ}
всього_знято = всього_далеких_до = всього_далеких_після = 0
print("%-26s %-13s %6s %6s %7s %8s %8s" % ("сцена", "слот", "пул", "знято", "перест.", "далеких↑", "далеких↓"))
for сцена, (lo, hi) in СЦЕНИ.items():
    for с in СЛОТИ:
        у = за_слотом[с]
        далекі_до = sum(1 for r in у if (КС._відстань_фото(r, lo, hi) or 0) >= 3)
        лишились, нота, лічба = КС._за_ошатністю_фото(list(у), с, (lo, hi))
        знято = len(у) - len(лишились)
        далекі_після = sum(1 for r in лишились if (КС._відстань_фото(r, lo, hi) or 0) >= 3)
        переставлено = sum(1 for a, b in zip(у, лишились) if a is not b)
        всього_знято += знято
        всього_далеких_до += далекі_до; всього_далеких_після += далекі_після
        if знято or далекі_до:
            print("%-26s %-13s %6d %6d %7d %8d %8d"
                  % (сцена, с, len(у), знято, переставлено, далекі_до, далекі_після))
print("РАЗОМ по 8 сценах: знято %d · речей, далеких від нагоди на 3+: ДО %d → ПІСЛЯ %d"
      % (всього_знято, всього_далеких_до, всього_далеких_після))
збої = sum(1 for сцена, (lo, hi) in СЦЕНИ.items() for с in СЛОТИ
           if not КС._за_ошатністю_фото(list(за_слотом[с]), с, (lo, hi))[0])
print("порожніх слотів після правила: %d" % збої)
print("ВПАЛО %d" % збої)
sys.exit(1 if збої else 0)
