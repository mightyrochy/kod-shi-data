"""Повторний перезбір Woo (13315): записи кольорів минулого прогону й запис обходу на тій самій сторінці — оновлено,
дублі вилучено з переходом номера й виміру, повтор того самого знімка сталий. Відмова 429 Store API — чекання, а
нуль товарів пише причину (13388)."""
import sys, types
from pathlib import Path
КОРІНЬ = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(КОРІНЬ / "zhnyvarka")]
import жниварка as ж, woo_варіанти as ва
Б, Р, М = "https://shop.test", dict(колір="pa_color", розмір="pa_size"), "shop.test"
ЖМ = types.SimpleNamespace(woo_рецепт=lambda д: Р, варіанти_woo=ж.варіанти_woo, факти_woo=ж.факти_woo, власник_варіанта_woo=ж.власник_варіанта_woo)

def товар(ід, сторінка, за_замовч):
    терми = [dict(name=н.upper(), slug=н, default=н == за_замовч) for н in "ab"]
    вар = [dict(ід=ід * 10 + і, адреса=Б + "/%s/?attribute_pa_color=%s" % (сторінка, н), є=True, кадри=[Б + "/%s.jpg" % н]) for і, н in enumerate("ab")]
    return dict(id=ід, name="Сукня", permalink=Б + "/%s/" % сторінка, type="variable", images=[dict(src=Б + "/%s.jpg" % н) for н in ("main", "a", "b")], _варіації=вар, attributes=[dict(taxonomy="pa_color", has_variations=True, terms=терми)])

def запис(ід, адреса, кадр, збирач):
    return dict(схема="v1", ід=ід, назва="Сукня", вихід={}, категорія="1", валюта="UAH", опис=None, ціна="100", адреса=Б + адреса, збирач=збирач,
                кадри=[Б + "/%s.jpg" % кадр], параметри=[["магазин", М, "с"], ["знято", "2026-10-16", "с"]])

def main():
    знімки = {М: [товар(1, "p1", "a"), товар(2, "p2", "b")]}
    старі = [запис("ж-00001", "/p1/?attribute_pa_color=a", "a", "адаптер"), запис("ж-00002", "/p2/?attribute_pa_color=b", "b", "адаптер"),
             запис("ж-00005", "/p1/?attribute_pa_color=b", "b", "адаптер"), запис("ж-00003", "/p1", "a", "обхід"), запис("ж-00004", "/p2", "b", "обхід")]
    зб = {"ж-00003@" + М: {"фото": Б + "/a.jpg"}, "ж-00005@" + М: {"фото": Б + "/b.jpg"}}
    нові, відп, з2, к2, звіт, _ = ва.перебрати(старі, знімки, ЖМ, зб, {}, "2026-11-05")
    assert sorted((з["ід"], з["адреса"]) for з in нові) == [("ж-00001", Б + "/p1/?attribute_pa_color=a"), ("ж-00002", Б + "/p2/?attribute_pa_color=b")], нові
    assert {р[1]: р[2] for р in відп if р[3].startswith("вилучено")} == {"ж-00003": "ж-00001", "ж-00004": "ж-00002", "ж-00005": "ж-00002"}
    assert sorted(з2) == ["ж-00001@" + М, "ж-00002@" + М] and all(ва._параметр(з, "знято") == "2026-11-05" for з in нові)
    повтор = ва.перебрати(нові, знімки, ЖМ, з2, к2, "2026-11-05")
    assert повтор[0] == нові and повтор[2] == з2 and not any(р[3].startswith("вилучено") for р in повтор[1])
    журнал, відповіді = [], iter([(429, ""), (200, '[{"id": 7, "permalink": "%s/p7/"}]' % Б)])
    т = ж.Транспорт(); т.підміна = lambda url: next(відповіді, (429, "", ""))[:2] + ("application/json",)
    ж.WOO_ПАУЗИ_ВІДМОВИ = (0,)
    assert [x["сирий"]["id"] for x in ж.woo_store_api(т, Б, журнал.append, 10)] == [7] and "HTTP 429" in журнал[0]
    assert ж.woo_store_api(т, Б, журнал.append, 10) == [] and журнал[-1].endswith("зупинено відмовою: HTTP 429")
    print("Woo повтор: 5 старих → 2 варіанти, 3 дублі з номером і виміром, повтор сталий; 429 — чекання, нуль — з причиною")

if __name__ == "__main__":
    main()
