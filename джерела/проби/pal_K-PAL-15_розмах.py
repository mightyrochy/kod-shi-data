# -*- coding: utf-8 -*-
"""K-PAL-15: розмах світлоти не губиться за «гучних > 1» і за одним голосом (рядок 1920).

(1) `набір_законний_заява` повертає УСІ вади: два гучні з розмахом 50 при низькому контрасті —
і `more_than_one_loud_colour`, і `lightness_range_off_her_contrast`; ремонт лишається.
(2) Суд образу рахує розмах по всіх кольорових речах: один голос L20…L75 (сумка й сережки
того самого тону) — зауваження розмаху. Запуск із `джерела`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import palettes as PAL, суд_від_моделі as СВ, colorspace as cs

коди = lambda з: [x["code"] for x in з]
_, _, з = PAL.набір_законний_заява([(25, 60), (75, 60)], "низький")
print("два гучні L25/L75:", коди(з))
assert коди(з) == ["more_than_one_loud_colour", "lightness_range_off_her_contrast"], з
_, ч, з = PAL.набір_законний_заява([(20, 60), (40, 20)], "низький", світлоти=[20, 40, 75])
print("пара + відлуння L75:", ч)
assert "lightness_range_off_her_contrast" in коди(з) and "55" in ч


def річ(і, сл, L, C, h):
    return {"id": і, "слот": сл, "lab": list(СВ._lab_з(L, C, h))}
П = {"вікна": {"L": [0, 100], "C": [0, 130], "сім_ї": []}}
for назва, речі, рівень in (
        ("один голос L20…L75, низький", [річ("a", "сумка", 20, 40, 150), річ("b", "прикраси", 75, 30, 150)], "низький"),
        ("два гучні L25/L75, низький", [річ("a", "верх", 25, 60, 30), річ("b", "низ", 75, 60, 250)], "низький")):
    зн = СВ.палітра_образу(речі, {"_палітра": П, "_контраст": рівень})
    z = next((x for x in зн if x.get("правило") == "K-PAL-15"), None)
    к = коди((z or {}).get("заяви") or [])
    print("%s: %s · ремонт=%s" % (назва, к, bool((z or {}).get("ремонт_заяви"))))
    assert z and "lightness_range_off_her_contrast" in к and z.get("ремонт_заяви"), z
