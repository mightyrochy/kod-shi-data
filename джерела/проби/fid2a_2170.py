"""Рядок 2170: речення опису з тире не стає назвою речі. Запуск: cd джерела && python3 проби/fid2a_2170.py
ДО (main): 28 з 702 речей `опис` лишали речення з тире за назву (feelyou 5: «Матеріали та наповнювач Плащівка з мембраною — …»), хоч у карті карток є заголовок."""
import collections, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, назва_речі as НР
оф = feed.читати_yml(feed.каталог_на_диску())[0]; карта = НР.читати_назви_карток()
оп = [o for o in оф if o["параметри"].get("назва_джерело") == "опис"]
р = {o["id"]: НР.назва_для_показу(dict(o, назва_показу=None), карта) for o in оп}
тире = [o for o in оп if " — " in o["назва"] or " – " in o["назва"]]
print("ФАКТ · назва_джерело=опис: %d речей; з тире між пробілами %d → джерела назви %s"
      % (len(оп), len(тире), dict(collections.Counter(р[o["id"]]["джерело"] for o in тире))))
for o in оп:
    if o["магазин"] == "feelyou.com.ua" and o["назва"].startswith("Матеріали"):
        print("ФАКТ · %s → «%s» (%s)" % (o["id"][:9], р[o["id"]]["назва"], р[o["id"]]["джерело"]))
