# -*- coding: utf-8 -*-
"""Що звіт каже про фото її речі в примірянні — по кожній руці прогонів власника.

`примірка_з` = скільки знімків ПОСЛАНО (з них її річ іде байтами з телефона),
`фото_речей` рахує лише `r.фото` — адресу крамниці (показ.html:2629), тож її річ
туди не потрапляє ніколи; `знімка_нема` (показ.html:2640) з тієї ж причини
називає її річ або «причина не названа», або «річ вигадана»."""
import json, glob, os
ТЕКА = os.path.join(os.path.dirname(__file__), "..", "..", "аудит", "тести", "власник_2026-09-25")
for шлях in sorted(glob.glob(os.path.join(ТЕКА, "*.json"))):
    d = json.load(open(шлях, encoding="utf-8"))
    print("=== %s" % os.path.basename(шлях))
    for п in d["прогони"]:
        закр = [р for р in ((п["спільне"].get("паспорт") or {}).get("речі_з_фото") or [])
                if р.get("закріплена")]
        if not закр:
            continue
        print(" прогін %s · закріплених речей з фото: %d (%s)"
              % (п["спільне"].get("розклад"), len(закр), ", ".join(р["ід"] for р in закр)))
        for в in п["вердикти"]:
            її = [r for r in (в.get("речі_образу") or []) if str(r.get("id", "")).startswith("її-")]
            нема = [z["річ"] for z in (в.get("знімка_нема") or [])]
            print("   рука %s | режим %-9s | примірка_з %s з %s | фото_речей %s | її речей у складі %d"
                  % (в["рука"], в.get("примірка_режим"), в.get("примірка_з"),
                     в.get("примірка_всього"), в.get("фото_речей"), len(її)))
            print("     знімка_нема: %s" % ("; ".join(нема) if нема else "—"))
            без = в.get("примірка_без_фото") or ""
            if без:
                print("     примірка_без_фото (жінці в підписі): %s" % без[:150])
