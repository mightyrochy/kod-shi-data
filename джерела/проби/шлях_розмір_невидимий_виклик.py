# -*- coding: utf-8 -*-
"""Складання/ремонт/вибір/повнота (показ.html:8060,8115/8138,8178/8190,8243) стоять
в ОДНОМУ зовнішньому try (8056) без свого catch: винятку тут (HTTP 413 тощо) нема куди
впасти, крім outer catch (8630: `рука N: збій — `), а `етапиВикликів.push(...)`
(7985) стоїть УСЕРЕДИНІ `відМоделіРуки` — тобто виконується лише ПІСЛЯ того, як
`модельПРуки` уже повернув відповідь. Отже запит, що впав до відповіді, не лишає
запису в `етапи.виклики` — лише рядок `діагноз_руки` без розміру й тексту.
Опис (8352) і перепис мови (8487), навпаки, МАЮТЬ свій `try{…}catch{…}` — їхня
помилка руку не валить. Факт із файлу власника 25.09: запит 428155 симв/HTTP 413
нема серед 4 записаних `виклики` (119893/94184/41588/5466 симв). Проба звіряє це
розташування в самому коді. Друкує факт.
Запуск: cd джерела && python3 проби/шлях_розмір_невидимий_виклик.py"""
import os
показ = open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                          "показ.html"), encoding="utf-8").read()

поч = показ.index("const однаРука = async (поз) =>")
зовн_try = показ.index("try{", поч)
зовн_catch = показ.index("ЗБ.діагноз.push('рука ' + рука + ': збій — '", зовн_try)
print("зовнішній try %d .. catch (збій=true) %d, %d симв між ними" % (зовн_try, зовн_catch, зовн_catch - зовн_try))

непідзахищені = [("складання", "модельПРуки(r.руки[рука], фотоРечейРуки"),
                  ("ремонт", "модельПРуки(в.промпт_ремонту"),
                  ("вибір", "модельПРуки(в.промпт_лише_вибору"),
                  ("повнота", "модельПРуки(в.промпт_повноти")]
for назва, підрядок in непідзахищені:
    поз_в = показ.index(підрядок, поч)
    у_зовн = зовн_try < поз_в < зовн_catch
    print("%-10s: виклик на %d — усередині зовнішнього try без catch: %s" % (назва, поз_в, у_зовн))
    assert у_зовн, "%s більше не в незахищеному блоці — перевір структуру заново" % назва

поз_опис = показ.index("модельП_блоки([...зФото, {type:'text', text:о.промпт}]", поч)
свій_catch_опису = показ.index("}catch(e){", поз_опис)
print("опис-з-фото на %d має СВІЙ catch на %d (до зовнішнього %d): %s"
      % (поз_опис, свій_catch_опису, зовн_catch, свій_catch_опису < зовн_catch))
assert свій_catch_опису < зовн_catch, "опис-з-фото втратив власний catch"

пуш = "етапиВикликів.push(етапВиклику(вхідний, вд, ЗБ.стадії[поз], запитОстанній));"
assert пуш in показ and показ.index(пуш) > показ.index("const вд = await містП('від_моделі', вхідний);")
print("запис у `виклики` — ПІСЛЯ успішної відповіді моста, не до неї")
