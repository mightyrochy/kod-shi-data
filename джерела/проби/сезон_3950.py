"""Рядок 3950: пора року з дати — у вході всіх чотирьох рук. Друкує `day` рук 1–2 (`день_кодами` нагоди з
`з_показу`) і `case` рук 3–4 (`випадок_кодами` → промпт руки) для тесту власника 14.10 (файл 1551, побачення
ввечері, дощ; +18 °C — вшите форми) і replay ЖИВІ-15 №12 (`seed3_01`, новорічний корпоратив). Дата — день прогону
(`сценарій.сьогодні` підмінено). Кращим: `season` у всіх чотирьох, градусів нема ніде (`unknown` у рук 1–2).
Запуск: cd джерела && python3 проби/сезон_3950.py (потрібні гілки `claude/vlasnyk-1410-1551`, `claude/zhyvi-15`)."""
import datetime, json, subprocess, sys
sys.path.insert(0, "."); import сценарій as СЦ, руки_без_коду as Р, мовний_шар as М
git = lambda *а: subprocess.run(["git", "-c", "core.quotepath=false", *а], capture_output=True, text=True).stdout
for г in ("claude/vlasnyk-1410-1551", "claude/zhyvi-15"):
    git("fetch", "-q", "origin", "%s:refs/remotes/origin/%s" % (г, г))
вер = json.loads(git("show", "origin/claude/vlasnyk-1410-1551:аудит/тести/власник_2026-10-14/"
                     "verdykty-0phxvk-2026-10-14-1551.json"))["спільне"]
сц12 = {"година": 11, "темп_c": 18, "типові_поля": ["година", "темп_c"]}         # форма №12 не торкана
т12 = git("show", "origin/claude/zhyvi-15:аудит/живі_15/А/12_ж2_корпоратив_виділитися/VIDPOVIDI/"
               "seed3_01_мовний_шар_хід_розмови.txt").split("── ВІДПОВІДЬ", 1)[1].split("──", 1)[1]
слова12 = ["новорічний корпоратив у ресторані, дрес-код коктейльний"]
п12 = М.паспорт_з_шару(М.прийняти_розмову(т12)["внутрішня"], сц12, слова_ходу=слова12)
п12 = п12[0] if isinstance(п12, tuple) else п12
СЦЕНИ = [("1551 побачення, дощ", вер["паспорт"], вер["вхід_прогону"]["сценарій"], вер["випадок_моделі"], "2026-10-14"),
         ("Ж15 №12 корпоратив", п12, сц12, "новорічний корпоратив", "2026-10-10"),
         ("Ж15 №12 корпоратив", п12, сц12, "новорічний корпоратив", "2026-12-19")]
ПОГОДА = ("season", "temperature_c", "weather_feel", "precipitation", "unknown")
for ім, п, сц, рядок, дата in СЦЕНИ:
    СЦ.сьогодні = lambda д=дата: datetime.date.fromisoformat(д)
    день = СЦ.день_кодами(СЦ.з_показу(сц, п)[0])
    print("── %s, дата %s | паспорт темп_c=%s (%s)" % (ім, дата, п.get("темп_c"), (п.get("джерело_полів") or {}).get("темп_c")))
    print("   руки 1–2 day:", {к: день[к] for к in ПОГОДА if к in день})
    for рука in ("3", "4"):
        case = json.loads(Р.промпт_руки(рука, Р.випадок_кодами(п, рядок, сценарій=сц)))
        case = next(в["value"] for в in case["input"] if в.get("name") == "case") if "input" in case else case.get("case")
        print("   рука %s case:" % рука, {к: case[к] for к in ПОГОДА if isinstance(case, dict) and к in case} or "—")
