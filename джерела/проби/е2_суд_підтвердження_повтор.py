"""Корінь Е2-межі, рядок 11779: суд підтвердження без зведення слів однієї пори й повтор перекладача словами.
argv[1] — корінь дерева коду (типово — це). Друкує по реченню: прийнято, причину прийняти_репліку і чи є
слова без опори в тексті повтору (`language_contract.пояснити_повтор`); підсумок — останнім рядком."""
import sys, os, json, warnings
warnings.filterwarnings("ignore")
ТУТ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(sys.argv[1] if len(sys.argv) > 1 else ТУТ, "джерела"))
import мовний_шар as М, language_contract as ЛК

ТЕАТР = dict(occasion=dict(label="Театр, концерт", quote="вечір у театрі, вистава о 19:00", source="her"))
ВИСТАВА = dict(occasion=dict(label="Театр, концерт", quote="сьогодні театр, вечірня вистава", source="her"))
ПОБАЧЕННЯ = dict(occasion=dict(label="Побачення", quote="побачення в ресторані о 19:30", source="her"),
                 part_of_day=dict(label="Ввечері", quote="о 19:30", source="her"))
ВИПАДКИ = [  # (текст, картка, чекаємо прийнято): ті самі слова картки — так; інше слово пори чи дня — повтор
    ("Записала: вечір у театрі, вистава о 19:00.", ТЕАТР, True),
    ("Записала: побачення в ресторані о 19:30, ввечері.", ПОБАЧЕННЯ, True),
    ("Так, я підібрала образ для театру о 19:00.", ТЕАТР, True),
    ("Так, я підібрала образ для вечора в театрі о 19:00.", ТЕАТР, False),
    ("Занотувала: побачення в ресторані о 19:30, вечірній час.", ПОБАЧЕННЯ, False),
    ("Я підібрала образ для сьогоднішнього театру, вечірньої вистави.", ВИСТАВА, False),
    ("Так, я підібрала образ для театру о 19:00. Це строгий соціальний вихід.", ТЕАТР, False),
]
л = dict(випадків=len(ВИПАДКИ), збіг_очікування=0, прийнято=0, відкинуто=0, повтор_зі_словами=0)
for текст, картка, чекаємо in ВИПАДКИ:
    р = М.прийняти_репліку(json.dumps({"text": текст}, ensure_ascii=False), dict(recorded=картка))
    прийнято = bool(р["текст"])
    слова = [с for в in р.get("відкинуто") or [] for с in в.get("слова") or []]
    повтор = ЛК.пояснити_повтор("РЕПЛІКА:\n{}", р.get("причина"), "РЕПЛІКА:\n") if р.get("причина") else ""
    зі_словами = bool(слова) and all(с in повтор for с in слова)
    л["збіг_очікування"] += прийнято == чекаємо
    л["прийнято" if прийнято else "відкинуто"] += 1
    л["повтор_зі_словами"] += зі_словами
    print("%s · %s · %s · %s" % ("так" if прийнято else "ні", р.get("причина") or "-", "слова в повторі"
                                if зі_словами else "-", текст))
print("ПІДСУМОК", json.dumps(л, ensure_ascii=False))
