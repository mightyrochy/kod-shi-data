# -*- coding: utf-8 -*-
"""K-SHO-01 (взуття й поділ — одне рішення), K-SHO-05 (халява — точка завершення),
K-SHO-06 (правила в корпусі нема — вимкнено чесно).

ДО ПРАВКИ: усі три стояли «у коді: —». K-SHO-01 жив рядком брифа й записом у
слід — інструктував модель і не судив нічого. K-SHO-05 працював механізмом, і
знахідка йшла під ID узагальнення K-SHO-11. K-SHO-06 не мав тексту в корпусі й
мовчав.
ПІСЛЯ: K-SHO-01 і K-SHO-05 стоять у `вердикт.образи[0].знахідки`, K-SHO-06 —
названим рядком черги на вхід."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
суди = lambda ід: ((json.loads(B.виклик("від_моделі", json.dumps(
    dict(вх, ід=ід), ensure_ascii=False))).get("вердикт") or {}).get("образи") or [{}])[0]

# ── K-SHO-01: поділ відомий, пари в образі нема ──────────────────────────────
сукня = next(c for c in кат if c.get("слот") == "сукня" and c.get("довжина_рівень"))
сумка = next(c for c in кат if c.get("слот") == "сумка")
о = суди([сукня["id"], сумка["id"]])
р = next((z for z in (о.get("знахідки") or []) if z.get("правило") == "K-SHO-01"), None)
print("K-SHO-01 · сукня «%s» довжина «%s», пари нема" % (сукня["назва"][:36], сукня["довжина_рівень"]))
print("   →", "НЕМА" if not р else "%s/%s %.2f · %s" % (р["сила"], р["регістр"], р["сила_нп"], р["суть"][:56]))
assert р, "без пари пропорція подолу не визначена — це мусить бути сказано"
# та сама сукня з парою: рядка нема, бо правило ВИКОНАНЕ
чобіт = next(c for c in кат if c.get("слот") == "взуття" and c.get("халява_рівень") == "литка")
о2 = суди([сукня["id"], сумка["id"], чобіт["id"]])
print("   з парою → K-SHO-01:", "нема (правило виконане)" if not next(
    (z for z in (о2.get("знахідки") or []) if z.get("правило") == "K-SHO-01"), None) else "Є")

# ── K-SHO-05: халява на найширшій точці литки ────────────────────────────────
# Профіль стенда литки НЕ міряє, і в шаблоні `areas` вона завжди вужча за коліно —
# локального максимуму на нозі не існує, і правило законно мовчить. Тут обхват
# литки подано як ВИМІР (`fit.тіло` приймає його й ставить T1), тобто правило
# судить на виміряному тілі, а не на популяційній середній.
вх_литка = dict(вх, обхвати=dict(вх["обхвати"], литка=42))
о5 = ((json.loads(B.виклик("від_моделі", json.dumps(
    dict(вх_литка, ід=[сукня["id"], сумка["id"], чобіт["id"]]), ensure_ascii=False))
    ).get("вердикт") or {}).get("образи") or [{}])[0]
р5 = next((z for z in (о5.get("знахідки") or []) if z.get("правило") == "K-SHO-05"), None)
print("K-SHO-05 · чобіт «%s» халява «%s», литку виміряно (42 см)"
      % (чобіт["назва"][:36], чобіт["халява_рівень"]))
print("   →", "НЕМА" if not р5 else "%s %.2f · %s" % (р5["сила"], р5["сила_нп"], р5["суть"][:56]))
assert р5, "халява на виміряній найширшій точці литки — це знахідка K-SHO-05, не K-SHO-11"

# ── K-SHO-06: названий рядок черги, а не тиша ────────────────────────────────
import accessory as АК
з6 = next(z for z in АК.без_входу() if z["правило"] == "K-SHO-06")
print("K-SHO-06 · %s/%s · %s" % (з6["сила"], з6["регістр"], з6["суть"][:60]))
print("   блокер:", з6["чому"][:96])
