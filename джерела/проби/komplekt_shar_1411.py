"""Рядок 1411 (КОМПЛЕКТ-1): блуза під піджаком/жилетом комплекту — шар, не «подвоєння верху».
ДО: «комплект + верх» — блокер завжди; ремонт повноти знімав блузу, `дотримати_склад` вертав її.
ПІСЛЯ: піджак/жилет + один верх — без блокера; сорочка-комплект + блуза, два верхи, комплект + низ —
блокер як доти; знятий верх поруч із цілою річчю ремонт назад не вертає (крім верху під шаром)."""
import sys, pathlib, collections
_К = pathlib.Path(__file__).resolve().parent.parent; sys.path.insert(0, str(_К))
import feed as Ф, суд_від_моделі as СМ, повнота_образу as PL
кат = {r["id"]: r for r in Ф._база_прогону(Ф.каталог_на_диску("каталог_повний.xml"), 0)["каталог"]}
наб = [r for r in кат.values() if r.get("набір") is True]
print("комплектів: %d · верх під шаром дозволено: %d" % (len(наб), sum(СМ.комплект_з_шаром(r) for r in наб)))
К = lambda н: dict(id="k", слот="комплект", тип="костюм", назва=н)
Р = lambda *сл: [dict(id="i%d" % n, слот=с, назва=н, тип=н) for n, (с, н) in enumerate(сл)]
ДОД = (("взуття", "лофери"), ("сумка", "сумка"), ("сережки", "сережки"))
def бл(комп, *сл):
    б = [x for x in СМ.структура_образу([К(комп)] + Р(*(сл + ДОД)), None, dict(нагода="робота", темп_c=18))
         if x.startswith("слот_двічі")]
    return "блокер" if б else "без блокера"
for назва, комп, сл in (("піджак + блуза", "Костюм двійка штани + піджак сірий", (("верх", "блуза"),)),
                        ("жилет + гольф", "Костюм штани палаццо + жилетка", (("верх", "гольф"),)),
                        ("класичний (з піджака) + сорочка", "Жіночий костюм з піджака та штанів", (("верх", "сорочка"),)),
                        ("сорочка-комплект + блуза", "Лляний костюм сорочка і палаццо", (("верх", "блуза"),)),
                        ("піджак + дві блузи", "Костюм піджак + штани", (("верх", "блуза"), ("верх", "топ"))),
                        ("піджак + штани", "Костюм піджак + штани", (("низ", "штани"),))):
    print("  %-34s → %s" % (назва, бл(комп, *сл)))
ном = {"k": (1, "01"), "b": (2, "02"), "s": (3, "03")}
поп = dict(образи=[dict(ід="о1", речі=["#1·01", "#2·02", "#3·03"], день="Речення про день")])
for комп in ("Костюм піджак + штани", "Лляний костюм сорочка і палаццо"):
    слов = {"k": dict(слот="комплект", назва=комп), "b": dict(слот="верх", назва="блуза"),
            "s": dict(слот="взуття", назва="лофери")}
    нові, повернуто = PL.дотримати_склад([["k", "s"]], поп, ном, слов)
    print("  ремонт зняв блузу (%s): повернуто %s" % (комп[:24], [п["річ"] for п in повернуто]))
print("  день після ремонту повноти:", PL.дні_до_ремонту([["k", "s"]], поп, ном))
