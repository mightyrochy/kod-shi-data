"""Виклик моделі, який УПАВ, у файл вердиктів не потрапляє — ні запитом, ні вагою.

ДО (main на 26.09.2026): запис кроку робив лише `відМоделіРуки`, тобто вже ПІСЛЯ
відповіді моста; `запитОстанній` лежав у замиканні й чекав наступної ВДАЛОЇ
відповіді. Приміряння не писало в `етапи` взагалі. Тому «HTTP 413 · запит 428 155
симв» у файлі власника є діагнозом і нема жодним викликом. Розмір теж рахувався
лише по тексту.
ПІСЛЯ: і `модельПРуки`, і `відМоделіРуки` пишуть запис на винятку (поле `помилка`),
приміряння пише свій (`крок: 'приміряння'`), а розмір стоїть трьома числами —
текст, base64 фото, разом.
Друкує місця записів у показі, наявність автозапису на винятку, і — на справжніх
файлах власника — найбільший ЗАПИСАНИЙ запит проти того, що каже діагноз.
"""
import json
import pathlib

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
рядки = (КОРІНЬ / "джерела" / "показ.html").read_text(encoding="utf-8").splitlines()
for н, р in enumerate(рядки, 1):
    if "етапиВикликів.push" in р or "запитОстанній = {" in р or "Приміряння не вдалось" in р:
        print("показ.html:%d" % н, р.strip()[:120])
ПОКАЗ = "\n".join(рядки)
print("   записів на винятку (`етапВиклику(..., e)`):", ПОКАЗ.count(", запитОстанній, e)"),
      "· полів розміру запиту:", ", ".join(п for п in ("символів", "фото_символів", "разом_символів")
                                           if "%s:" % п in ПОКАЗ) or "—")
прим = next(i for i, р in enumerate(рядки) if "async function приміряти(поз)" in р)
кін = next(i for i, р in enumerate(рядки) if i > прим and р.startswith("}"))
тіло = "\n".join(рядки[прим:кін])
print("   тіло `приміряти` (%d рядків): записів у `етапи.виклики` %d · із них на винятку %d"
      % (кін - прим, тіло.count("записатиВикликПримірки(") - 1,   # -1 — саме оголошення
         тіло.count("null, e); throw e; }")))

ф = КОРІНЬ / "аудит" / "тести" / "власник_2026-09-25" / "verdykty-0phxvk-2026-09-25-2012.json"
д = json.loads(ф.read_text(encoding="utf-8"))
for п in д["прогони"]:
    for в in п["вердикти"]:
        е = в.get("етапи") or {}
        симв = [(в2.get("крок"), (в2.get("запит") or {}).get("символів")) for в2 in (е.get("виклики") or [])]
        збій = [р for р in (е.get("діагноз_руки") or []) if "збій" in р or "не вдал" in р]
        if збій:
            print("розклад", п["спільне"].get("розклад"), "· рука", в.get("рука"),
                  "· `викликів`:", в.get("викликів"), "· записано кроків:", len(симв))
            print("   найбільший ЗАПИСАНИЙ запит:", max((с or 0) for _, с in симв) if симв else 0,
                  "симв · діагноз каже про:", збій[0][-90:])
