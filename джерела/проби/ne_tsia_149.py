# -*- coding: utf-8 -*-
"""ПОЗНАЧКА «НЕ ЦЯ» → МІСТ → ПУЛ (рядок 149).

Картка обіцяє жінці: «познач «не ця» на речі, і образ зберуть заново». Проба
міряє, чи обіцянка правдива: той самий прогін двічі — без поля `не_ця` і з ним,
на тій самій речі, і скільки знято під яким іменем у `відсічено.лічба`.
Запуск: cd джерела && python3 проби/ne_tsia_149.py
"""
import json, pathlib, sys
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import bridge as B, feed as Ф, pipeline as PL

вх = dict(json.load(open(_К / "стенд_вх.json", encoding="utf-8")),
          каталог=Ф.каталог_на_диску(), варіантів=1, гілка=0)
без = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
пул = lambda r, сл: [x["id"] for x in ((r.get("кандидати") or {}).get(сл) or [])]
донор = lambda r, сл: [x["id"] for x in ((r.get("кандидати_донора") or {}).get(сл) or [])]
# річ із пулу ОБОХ рук із каталогом: інакше «рука 2 її не дістала» читалось би
# як доказ там, де її в неї й не було
слот, ціль = [(с, x) for с in ("сумка", "взуття", "верх", "низ")
              for x in пул(без, с) if x in донор(без, с)][0]
з = json.loads(B.виклик("запити", json.dumps(dict(вх, не_ця=[ціль]), ensure_ascii=False)))

лічба = lambda r: ((r.get("відсічено") or {}).get("лічба") or {})
print("слот «%s»: рука 1 до %d речей, після %d · позначена річ «%s»"
      % (слот, len(пул(без, слот)), len(пул(з, слот)), ціль))
print("   рука 1: позначена річ у пулі ДО — %s · ПІСЛЯ — %s"
      % (ціль in пул(без, слот), ціль in пул(з, слот)))
print("   рука 2: позначена річ у пулі ДО — %s · ПІСЛЯ — %s"
      % (ціль in донор(без, слот), ціль in донор(з, слот)))
print("   відсічено.лічба ДО:    %s" % json.dumps(лічба(без), ensure_ascii=False))
print("   відсічено.лічба ПІСЛЯ: %s" % json.dumps(лічба(з), ensure_ascii=False))
print("   ім'я відсічення: «%s» · знято під ним: %d"
      % (PL.ПРИЧИНА_НЕ_ЦЯ, лічба(з).get(PL.ПРИЧИНА_НЕ_ЦЯ, 0)))
assert ціль in пул(без, слот) and ціль not in пул(з, слот), "позначена річ лишилась у пулі руки 1"
assert ціль not in донор(з, слот), "позначена річ лишилась у пулі руки 2"
assert лічба(з).get(PL.ПРИЧИНА_НЕ_ЦЯ), "відсічення без власного імені в лічбі"
assert PL.ПРИЧИНА_НЕ_ЦЯ not in лічба(без), "ім'я відсічення з'явилось без жодної позначки"
