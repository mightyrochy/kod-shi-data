"""Рядок 1996: калібрування журналу (`вердикт_моделі.калібрування`) — дві вади звіту.
(1) без контролю: правило стоїть у КОЖНОМУ образі журналу, «без нього» порожньо, і різниця
    рахувалась проти 0 — число, хоч порівнювати нема з чим; (2) ключ спостереження —
    склад образу (`"+".join(id)`), тож той самий образ двох днів зливався в одну подію.
Журнал синтетичний (ваг не міняє, моделі не кличе); сцени — з реального шляху показу:
`вердикт_у_ребра` на кожен вердикт, `подія` — номер запису журналу (`малюватиКалібруванняП`).
Запуск: cd джерела && python3 проби/калібрування_контроль_1996.py"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import вердикт_моделі as В
о = lambda *ід: {"речі": [{"id": i} for i in ід], "знахідки": [{"правило": "K-COL-01", "сила_нп": 0.4}]
                                                             + ([{"правило": "K-FIT-03", "сила_нп": 0.3}] if "сукня" in ід else [])}
# той самий образ «сукня+туфлі» у два дні: «вдягну як є», потім «не вдягну»; третій образ — інший
дні = [("вдягну як є", о("сукня", "туфлі")), ("не вдягну", о("сукня", "туфлі")), ("не вдягну", о("штани", "туфлі"))]
записи = []
for п, (верд, в) in enumerate(дні):
    записи += [dict(р, подія=п) for р in В.вердикт_у_ребра(верд, в)]
к = В.калібрування(записи, мінімум=1)
for р in sorted(к):
    з = к[р]
    print("%-9s подій з ребром %d, без %d · різниця %s · %s" % (р, з["образів_з"], з["образів_без"],
          "нема порівняння" if з["різниця"] is None else з["різниця"], з["тір"]))
print("ФАКТ · подій у журналі %d; K-COL-01 стоїть у кожній — контролю нема; «сукня+туфлі» — два дні" % len(дні))
