# -*- coding: utf-8 -*-
"""Рядок 118: чиє фото показує картка. ДО — правило main (кадр жнив звіряється цілим
рядком, інакше `фото[0]`); ПІСЛЯ — `bridge.показ` цієї гілки. На весь каталог: карток
із картинкою, спільною ще з ≥ 4 речами крамниці (логотип), із дрібною ≤ 150×150, без
фото взагалі; окремим рядком — скільки дістали знімок ЗАПАСНИМ шляхом (кадр жнив,
якого у фіді нема, коли фід не дав нічого свого); плюс дві речі власника поіменно."""
import sys, json, pathlib, collections
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import bridge as B, feed as F, міст_опис as МО
ш = F.каталог_на_диску(); оф = F.читати_yml(ш)[0]; зб = F.читати_збагачення()
за_ід = {o["id"]: o for o in оф}; мг = lambda o: o.get("магазин") or str(o["id"]).split("@")[-1]
речей = collections.defaultdict(collections.Counter)
for o in оф:
    for ф in {МО._файл_фото(x) for x in (o.get("фото") or []) if x}: речей[мг(o)][ф] += 1
def до(o):
    """Вибір main: кадр збагачення, лише коли він у списку цілим рядком."""
    фф = [x for x in (o.get("фото") or []) if x]; к = (зб.get(o["id"]) or {}).get("фото")
    return к if (к and к in фф) else (фф[0] if фф else None)
після = {к["id"]: к.get("фото") for к in json.loads(B.показ(dict(каталог=ш, речі=list(за_ід))))}
запасний = lambda o, u: bool(u) and МО._файл_фото(u) not in речей[мг(o)]
def міри(беру):
    """(спільне з ≥ 4 іншими речами, дрібне ≤ 150×150, без фото) на весь каталог."""
    сп = др = пусто = 0
    for o in оф:
        u = беру(o)
        if not u: пусто += 1; continue
        п = МО._площа_фото(u); сп += речей[мг(o)][МО._файл_фото(u)] >= 5
        др += (п is not None and п <= 150 * 150)
    return сп, др, пусто
підпис = lambda o, u: ("%s · %s%s" % (u.split("/")[-1], ("%d пікс" % МО._площа_фото(u))
    if МО._площа_фото(u) else "розмір не в шляху",
    " · КАДР ЖНИВ, запасним шляхом" if запасний(o, u) else "")) if u else "— (нема фото)"
print("каталог %s · речей %d · поріг СПІЛЬНЕ_ФОТО_ТОВАРІВ = %d (різних товарів на файл)\n"
      "%-7s %9s %9s %9s" % (pathlib.Path(ш).name, len(оф), МО.СПІЛЬНЕ_ФОТО_ТОВАРІВ,
                            "", "спільне", "дрібне", "без фото"))
for імя, беру in (("ДО", до), ("ПІСЛЯ", lambda o: після.get(o["id"]))):
    print("%-7s %9d %9d %9d" % ((імя,) + міри(беру)))
print("з них запасним шляхом: %d карток" % sum(запасний(o, після.get(o["id"])) for o in оф))
for ід in ("ж-09320@emmeliedelage.com", "ж-07847@giardini-shoes.com"):
    print("%s · %s\n   ДО    %s\n   ПІСЛЯ %s" % (ід, за_ід[ід].get("назва"),
          підпис(за_ід[ід], до(за_ід[ід])), підпис(за_ід[ід], після.get(ід))))
