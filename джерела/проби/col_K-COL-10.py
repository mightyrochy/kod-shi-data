# -*- coding: utf-8 -*-
"""K-COL-10 (мікс принтів) — ціле, перевірено пробою.

Корпус (тема-4:8288): «спільна колірна нитка + різні масштаби + один принт
домінує. Без спільного кольору мікс розпадається. Класичні пари: смужка +
квітковий, горох + клітинка. FORCE: strong, [convention]».
ДВА ВИРОБНИКИ, ОБИДВА ЖИВІ, І ДЕДУП МІЖ НИМИ СТОЇТЬ ЗА ПРАВИЛОМ, НЕ ЗА РЕЧАМИ
(`pipeline._ЗА_ПРАВИЛОМ`): `колір_образу.принти` судить ВИДИМІ речі станів образу,
`pipeline._доповнення_судді` — усі речі за назвою. Набори речей у них різні, тож
ключ «(правило, речі)» пропускав дубль, і стиліст читав одну проблему тричі.
Проба бере класичну пару корпусу — смужка + квітковий.
Запуск із теки `джерела`: `python3 проби/col_K-COL-10.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import pipeline as PL

візерунок = lambda який: (lambda L, C, h, з: str(з.get("візерунок") or "").lower() == який)
вх, r, кат, спец = ПВ.стенд(гілка=0)
верх = ПВ.з_каталогу(кат, "верх", візерунок("смужка"))
низ = ПВ.з_каталогу(кат, "низ", візерунок("квітковий"))
print("класична пара корпусу «смужка + квітковий»:")
for с, x in (("верх", верх), ("низ", низ)):
    print("   %-5s «%s» · візерунок «%s» · тон %.0f°"
          % (с, x["назва"][:40], x["візерунок"], ПВ.lch(кат, x["id"])[2]))
ід = [верх["id"], низ["id"]] + [x["id"] for с in ("взуття", "сумка")
                                for x in (r["кандидати"].get(с) or [])[:1]]
зн, _ = ПВ.знахідки(вх, ід)
рядки = [x for x in зн if x.get("правило") == "K-COL-10"]
print("ФАКТ · K-COL-10: %s" % ПВ.рядок(зн, "K-COL-10"))
print("       рядків у вердикті: %d (дедуп за правилом, не за набором речей)" % len(рядки))
assert len(рядки) == 1, рядки
z = рядки[0]
assert z["сила"] == "strong" and z["сила_нп"] == 0.75, z          # корпусна сила
assert z["регістр"] == "репліка" and z["ремонт"], z    # [convention] — не гейт
import inspect                            # дедуп за правилом — у коді, не в переказі
assert '_ЗА_ПРАВИЛОМ = ("K-COL-10",)' in inspect.getsource(PL.перевірити_від_моделі)
print("       ремонт: %s" % z["ремонт"])
