# -*- coding: utf-8 -*-
"""K-COL-JOIN (злиття вікон на одному носії) — вимкнено чесно, і вага 0.0 тут не баг.

Корпус: «WHEN: перетин НЕпорожній. FORCE: вага 0.0 — ранг не змінюється взагалі.
У каталог іде ОДНЕ спільне вікно замість двох окремих запитів. Дзеркальний бік
K-COL-CONF: там, де правила сходяться, система не має права питати двічі».
ДВІ РЕЧІ, ЯКІ ПРОБА СТВЕРДЖУЄ ОКРЕМО.
1. Вага 0.0 означає, що рядка у вердикті в цього правила НЕМА І НЕ МАЄ БУТИ:
   `pipeline._питання_або_нуль` відкидає нульові, і це рівно те, що просить
   корпус. Наслідок правила — `запит_у_каталог` зі СПІЛЬНИМ вікном, і саме його
   проба й міряє.
2. Входу на живому шляху нема з тієї самої причини, що в K-COL-CONF: тест парний,
   а вікно віддає одне правило. Це видно чеклістом 18 `суд_образу`.
Запуск із теки `джерела`: `python3 проби/col_K-COL-JOIN.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import колір_образу as КО, pipeline as PL

# ДВА ВІКНА, ЩО ПЕРЕТИНАЮТЬСЯ: те, чого живий вхід не дає (див. col_K-COL-CONF.py).
злиття = КО.несумісні_ремонти([
    dict(правило="K-CLR-02", речі=["сумка"], запит_у_каталог=dict(слот="сумка", цільова_L=[60.0, 92.0])),
    dict(правило="K-COL-01", речі=["сумка"], запит_у_каталог=dict(слот="сумка", цільова_L=[70.0, 88.0]))])
z = next((x for x in злиття if x["правило"] == "K-COL-JOIN"), None)
assert z, "два вікна, що перетинаються, не дали K-COL-JOIN"
q = z["запит_у_каталог"]
print("два запити L*(60,92) і L*(70,88) на носій «сумка» → один: %s · %s"
      % (q["слот"], q["цільова_L"]))
assert q["цільова_L"] == [70.0, 88.0], q          # найвужчий спільний, а не перший-ліпший
print("ФАКТ · K-COL-JOIN: сила %s, вага %.2f, регістр %s — ранг не змінює за корпусом"
      % (z["сила"], z["сила_нп"], z["регістр"]))
assert z["сила_нп"] == 0.0 and z["регістр"] == "репліка", z
assert PL._питання_або_нуль(z) is True, "вага 0.0 мусить лишати правило поза рядками вердикту"
print("       рядка у вердикті нема НАВМИСНО: `_питання_або_нуль` відкидає нульові,")
print("       наслідок правила — одне спільне вікно в каталог, а не зауваження жінці")
# КОНФЛІКТ І ЗЛИТТЯ — ВЗАЄМНО ВИКЛЮЧНІ: на тій самій парі не буває обох.
assert not any(x["правило"] == "K-COL-CONF" for x in злиття), злиття
print("       на непорожньому перетині K-COL-CONF мовчить — дзеркальні боки одного тесту")
