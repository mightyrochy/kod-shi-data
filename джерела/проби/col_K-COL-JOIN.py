# -*- coding: utf-8 -*-
"""K-COL-JOIN (злиття вікон на одному носії) — спільне вікно доїжджає до каталогу.

Корпус: «WHEN: перетин НЕпорожній. FORCE: вага 0.0 — ранг не змінюється взагалі.
У каталог іде ОДНЕ спільне вікно замість двох окремих запитів. Дзеркальний бік
K-COL-CONF: там, де правила сходяться, система не має права питати двічі».
ЩО БУЛО ДО 18.09.2026. Вхід правила зʼявився аж зі збагаченням каталогу (колір
пулу 0 → 92 %): K-CLR-02 ожив і почав просити вікно на «верх|шарф», а K-KOH-06
просив своє на «шарф» — вони ПЕРЕТИНАЮТЬСЯ, тобто це рівно випадок злиття. Але
правило народжувалось із вагою 0.0 і за рядок по тому гинуло в підлозі
(`реєстр_правил.обмежити_вагу` → `під_підлогою` → фільтр `review`). Підлога
мовчить про слабку ДУМКУ, а тут думки нема — є запит у каталог; вага 0.0 в нього
не від слабкості виміру, а з корпусу дослівно. Виняток названий іменем:
`реєстр_правил.ВАГА_НУЛЬ_ЗА_КОРПУСОМ`.
Запуск із теки `джерела`: `python3 проби/col_K-COL-JOIN.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import суд_образу as СО, composer as КМ, pipeline as PL, реєстр_правил as РЕЄСТР

сц = dict(нагода="робота", місце="офіс", година=9, темп_c=18, дрес_код="business_casual")
вх, r, кат, спец = ПВ.стенд(гілка=0, сценарій=сц)
F, *_ = ПВ.B._features(вх)          # та сама особа, якою ходить живий шлях
за_ід = {c["id"]: c for c in ПВ.B.каталог_останнього_пакета()}
ід = [(r["кандидати"].get(с) or [None])[1 % max(1, len(r["кандидати"].get(с) or [1]))]
      for с in ("верх", "низ", "взуття", "сумка", "шарф", "прикраси")]
ід = [x["id"] for x in ід if x]
речі = [КМ._у_річ(dict(за_ід[x]), за_ід[x]["слот"], вх.get("тіло")) for x in ід if x in за_ід]
рез = СО.review(F, речі, нагода=сц["нагода"], дрес_код=сц["дрес_код"], сцен=сц, темп_c=18)
зн = [z for d in рез["стани"].values() for z in d["знахідки"]]
z = next((x for x in зн if x["правило"] == "K-COL-JOIN"), None)
assert z, "два ремонти на «шарф» перетинаються, а злиття не вийшло"
окремі = [q for d in рез["стани"].values() for q in (d.get("запити") or [])
          if q.get("слот") and "шарф" in str(q["слот"]) and "цільова_L" in q]
print("запитів на «шарф» у каталог: %d" % len(окремі))
for q in окремі:
    print("   L*%s · %s" % (q["цільова_L"], str(q.get("чому"))[:46]))
print("ФАКТ · K-COL-JOIN: вага %.2f, регістр %s — одне спільне вікно L*%s замість двох"
      % (z["сила_нп"], z["регістр"], z["запит_у_каталог"]["цільова_L"]))
assert z["сила_нп"] == 0.0 and "K-COL-JOIN" in РЕЄСТР.ВАГА_НУЛЬ_ЗА_КОРПУСОМ, z
assert z["запит_у_каталог"]["цільова_L"] == [48.0, 76.0], z    # найвужчий спільний
assert PL._питання_або_нуль(z) is True, "рядка у вердикті в нього бути не має"
print("       рядка у вердикті нема НАВМИСНО: ранг не змінюється, міняється ЗАПИТ")
