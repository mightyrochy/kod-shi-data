"""НП-в: норма події — поля мовної моделі `reserved_colour` і `open_zones`, рух одним переліком.
Друкує: (1) майже-білі великі поверхні каталогу в пулі `_придатні` на весіллі гостею — без вето
(як доти) і з полем моделі; (2) ліміт K-KOH-10 обох суддів на похороні/церкві з поля і без;
(3) рух «танцювати» від мовної моделі → паспорт → enum ВИПАДКУ. Запуск із `джерела`."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import feed as Ф, мовний_шар as МШ, сценарій as СЦ, композитор_придатні as КП, формальність as ФОРМ
import суд_від_моделі as СВМ, протокол as ПР
кат = Ф._база_прогону(Ф.каталог_на_диску("каталог_повний.xml"))["каталог"]
def сцена(внутрішня, плитка, слова=""):
    п = МШ.паспорт_з_шару(внутрішня, плитка, None, {}, слова_ходу=слова)["паспорт"]
    return п, СЦ.з_показу(плитка, п)[0]
_, весілля = сцена({"occasion": "wedding_guest", "formality": {"from": 7, "to": 9},
                    "reserved_colour": "near_white", "open_zones": "one"}, {"нагода": "весілля_гість"})
print("сцена весілля: зарезервований_колір=%s відкриті_зони=%s" % (весілля.get("зарезервований_колір"), весілля.get("відкриті_зони")))
_вето = ФОРМ.вето_майже_білого
ФОРМ.вето_майже_білого = lambda с: False
до = sum(map(ФОРМ.майже_біла_річ, КП._придатні(кат, None, None, None, весілля)[0]))
ФОРМ.вето_майже_білого = _вето
пул, відк = КП._придатні(кат, None, None, None, весілля)
print("весілля гостею: майже-білих великих поверхонь у пулі до %d → після %d · %s"
      % (до, sum(map(ФОРМ.майже_біла_річ, пул)), [(в["причина"], в["скільки"]) for в in відк if "near_white" in в["причина"]]))
print("без поля моделі (плитка «щоденне», місця нема): вето =", ФОРМ.вето_майже_білого(сцена({"occasion": "everyday"}, {"нагода": "щоденне"})[1]))
речі = [{"id": "с1", "назва": "сукня міні без рукавів", "слот": "сукня"}]
for ключ, код, зони in (("траур", "mourning", "none"), ("церква", "church", "none"), ("театр", "theatre", None)):
    вн = dict({"occasion": код}, **({"open_zones": зони} if зони else {}))
    for з_полем in ((True, False) if зони else (False,)):
        сц = сцена(вн if з_полем else {"occasion": код}, {"нагода": ключ, "година": 11})[1]
        kk = [з for з in СВМ._доповнення_судді(речі, сц) if з.get("правило") == "K-KOH-10"]
        print("%-7s поле %-5s → ліміт %s · K-KOH-10 суду моделі: %s" % (ключ, сц.get("відкриті_зони"),
              ФОРМ.ліміт_відкритих_зон(сц.get("відкриті_зони"), False)[0], kk[0]["суть"][:60] if kk else "мовчить"))
п = сцена({"movement": "dance", "quotes": {"movement": "танцюватимемо"}}, {"нагода": "свято"}, "танцюватимемо до ранку")[0]
print("рух «танцюватимемо» → паспорт рух=%r · у enum ВИПАДКУ: %s · event_movement у мові: %s"
      % (п.get("рух"), п.get("рух") in ПР.ВИПАДОК["поля"]["рух"]["значення"], "event_movement" in МШ._ВМ.ТАБЛИЦЯ))
