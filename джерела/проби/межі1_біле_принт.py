E = [dict(річ=н, слот=сл, L=92, C=6, lab=(92, 2, 6), площа=0.03, near=NEAR[сл])
     for н, сл in (("шарф молочний", "шарф"), ("капелюх білий", "головний_убір"), ("сережки перли", "сережки"))]
for з in Ф.нагода_палітра(E, нагода="весілля"):
    if з["правило"] == "K-KOH-08" and "майже-біле" in з["суть"]:
        print("K-KOH-08 · %-14s %-4s нп=%.2f · %s" % (з["речі"][0], з["сила"], з["сила_нп"], з["суть"]))
п = {"подія": "весілля подруги", "зарезервований_колір": "near_white"}
