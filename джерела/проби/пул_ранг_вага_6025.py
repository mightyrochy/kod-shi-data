# -*- coding: utf-8 -*-
"""Рядок 6025: частка речей У СМУЗІ рангу нагоди (ошатність типу перетинає смугу, `композитор_слоти._ранг_нагоди`)
у квоті семплера за слотами — «йога зранку» (спорт 1–2, вхід живого 15/13), музей, прогулянка; контроль — робота
з числом ошатності (ранг не діє: відбиток id пулу має бути тим самим ДО і ПІСЛЯ). Рядок слота: «у смузі / квота
(у смузі на вході семплера)», суми за сідами. Аргумент — вага `семплер.ВАГА_НАГОДИ` для замірів.
Запуск із теки `джерела`: python3 проби/пул_ранг_вага_6025.py [вага]"""
import sys, os, json, hashlib, collections
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge as B, feed as Ф, семплер as С, композитор_слоти as КС, композитор_придатні as КП
if len(sys.argv) > 1: С.ВАГА_НАГОДИ = float(sys.argv[1])
База = dict(json.load(open("стенд_вх.json", encoding="utf-8")), шкіра="#d9b48f", волосся=["#745a3b"], очі="#7a7a4c",
            каталог=Ф.каталог_на_диску("каталог_повний.xml"))
СЦЕНИ = {"йога зранку": dict(нагода="спорт", місце="спорт", година=11, темп_c=18),
         "музей": dict(нагода="музей", місце="музей", година=14, темп_c=18),
         "прогулянка": dict(нагода="прогулянка", місце="парк", година=15, темп_c=18),
         "робота 09:00": dict(нагода="робота", місце="офіс", година=9, темп_c=18, дрес_код="business_casual")}
вхід, _вибрати = {}, С.вибрати
def _вибрати_з_обліком(кандидати, *а, **kw):
    """Вхід семплера за слотами — скільки речей пулу в смузі до вибірки."""
    вхід.update(кандидати); return _вибрати(кандидати, *а, **kw)
С.вибрати = _вибрати_з_обліком
for н, сц in СЦЕНИ.items():
    смуга, Л, відбиток = КП.смуга_рангу(сц), collections.defaultdict(collections.Counter), hashlib.md5()
    for сід in range(1, 9):
        вхід.clear()
        r = json.loads(B.виклик("запити", json.dumps(dict(База, сід=сід, сценарій=сц, паспорт=dict(сц), випадок=н), ensure_ascii=False)))
        for с, рч in sorted(r["кандидати"].items()):
            відбиток.update((с + ",".join(str(x.get("id")) for x in рч)).encode())
            if смуга and с in ("верх", "низ", "верхній_шар", "взуття", "комплект", "сукня"):
                у = lambda xs: sum(1 for x in xs if КС._ранг_нагоди(x, смуга)[0] == 0)
                Л[с] += collections.Counter(у=у(рч), квота=len(рч), вхід=у(вхід.get(с) or []))
    print("%s (смуга %s, 8 сідів, відбиток %s)" % (н, смуга, відбиток.hexdigest()[:10]))
    for с, к in sorted(Л.items()):
        print("  %s: у смузі %d / квота %d (%.0f %%), у смузі на вході %d" % (с, к["у"], к["квота"], 100 * к["у"] / max(1, к["квота"]), к["вхід"]))
