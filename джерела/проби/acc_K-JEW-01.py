# -*- coding: utf-8 -*-
"""K-JEW-01: усі придатні пари каталогу утримуються від судження й доходять до вердикту."""
import sys, pathlib, json, collections
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, accessory as АК, fit as ПС, внутрішня_мова as М

def головна():
    """Звіряє нульову вагу, видиму причину невідомого та відсутній вхід ланцюга."""
    вх = json.loads((_КОРІНЬ / "стенд_вх.json").read_text(encoding="utf-8"))
    вх.update(каталог=Ф.каталог_на_диску("каталог_повний.xml"), гілка=0)
    json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    кат = B.каталог_останнього_пакета()
    тіло = ПС.тіло(float(вх["зріст"]), {к: float(в) for к, в in вх["обхвати"].items()})
    прик = [р for р in кат if р.get("ланцюг_см") is not None and р.get("слот") in АК.ЛАНЦЮГОВІ_СЛОТИ
            and not М.тип_на_голові(р.get("тип"))]
    сукні = [р for р in кат if р.get("слот") == "сукня" and р.get("виріз_тип") in АК.ГЛИБИНИ_ВИРІЗУ]
    assert прик and сукні, "каталог не дав кольє з довжиною або сукні з горловиною"
    пар = collections.Counter()
    for в in сукні:
        for п in прик:
            з, = АК.кольє_проти_горловини(тіло, [в, п])
            assert з["сила"] == "утримано" and з["сила_нп"] == 0
            пар[в["виріз_тип"]] += 1
    print("кольє", len(прик), "горловин", len(сукні), "утриманих пар", sum(пар.values()), dict(пар))
    сук, кол = сукні[0], прик[0]
    взут = next(р for р in кат if р.get("слот") == "взуття")
    вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=[сук["id"], взут["id"], кол["id"]]), ensure_ascii=False)))
    о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
    з = next((р for р in (о.get("знахідки") or []) if р.get("правило") == "K-JEW-01"), None)
    assert з and з["сила"] == "утримано" and з["сила_нп"] == 0, "утриманий вимір не доїхав у вердикт"
    if тіло["висоти"].get("основа_шиї") is None:
        assert "нема точки" in АК.кольє_проти_горловини(тіло, [сук, кол])[0]["чому"], "брак основи шиї не пояснено"
    print("K-JEW-01 у вердикті:", з["сила"], з["сила_нп"], з["суть"])
    без_ланцюга = dict(кол); без_ланцюга.pop("ланцюг_см")
    assert АК.кольє_проти_горловини(тіло, [сук, без_ланцюга]) == [], "без довжини ланцюга немає пари для оцінки"


if __name__ == "__main__":
    головна()
