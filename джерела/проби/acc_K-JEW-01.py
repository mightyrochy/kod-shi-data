# -*- coding: utf-8 -*-
"""K-JEW-01 (кольє не має збігатися з краєм горловини) — обидва краї від однієї точки.

ДО ПРАВКИ два розриви, і другий важить більше.
  1. `ланцюг_см` не писав НІХТО: правило шукало поле без постачальника.
  2. За край горловини бралось `верх_см` речі, а на живому шляху `composer._у_річ`
     ставить верху й сукні `верх_см` із ДЕФОЛТУ СЛОТА — і дефолт цей рівно
     `висоти["плечі"]`, тобто та сама точка, від якої відкладається падіння
     ланцюга. Зазор дорівнював ПОЛОВИНІ ЛАНЦЮГА завжди: 41 см → 20.5 при порозі
     5.0. Правило не могло спрацювати ні на чому.
ПІСЛЯ: ланцюг читається з картки (52 речі пакета), а край горловини — з `виріз_тип`
(1 538 оферів каталогу) через `ГЛИБИНИ_ВИРІЗУ`. Проба друкує, на скількох парах
«верх × прикраса» правило спрацьовує, і показує рядок вердикту."""
import sys, pathlib, json, collections
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, accessory as АК, fit as ПС

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
T = ПС.тіло(float(вх["зріст"]), {k: float(v) for k, v in вх["обхвати"].items()})
прик = [c for c in кат if c.get("ланцюг_см") is not None]
сукні = [c for c in кат if c.get("слот") == "сукня" and c.get("виріз_тип")]
пар = collections.Counter()
for в in сукні:
    for п in прик:
        if АК.кольє_проти_горловини(T, [dict(в), dict(п)]):
            пар[в["виріз_тип"]] += 1
print("прикрас із ланцюгом %d · суконь із типом вирізу %d · пар зі знахідкою %d із %d"
      % (len(прик), len(сукні), sum(пар.values()), len(сукні) * len(прик)))
print("   за вирізом:", dict(пар))
сук = next(c for c in сукні if c["виріз_тип"] == "V-подібний")
кол = next(c for c in прик if c["ланцюг_см"] == 41.0)
взут = next(c for c in кат if c.get("слот") == "взуття")
вм = json.loads(B.виклик("від_моделі", json.dumps(
    dict(вх, ід=[сук["id"], взут["id"], кол["id"]]), ensure_ascii=False)))
о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
р = next((z for z in (о.get("знахідки") or []) if z.get("правило") == "K-JEW-01"), None)
print("K-JEW-01 у вердикті:", "НЕМА" if not р else
      "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:76]))
assert р and пар, "кольє проти горловини мусить спрацьовувати й доїжджати у вердикт"
assert sum(пар.values()) < len(сукні) * len(прик), "правило мусить і мовчати"
