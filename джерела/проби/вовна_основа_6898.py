# Рядок 6898: `вовна_частка` з основи, не з param. Друкує на каталог_повний: речей з названою часткою, з 1.0 і речей, де
# основа (`матеріал_речі`) слів «вовн/шерст/wool» не має, а частка ≥0.5 (N). ПІСЛЯ: N = 0.
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed as Ф
from фід_атрибути import матеріал_речі
кат = Ф._прочитати_каталог(Ф.каталог_на_диску("каталог_повний.xml"), ліміт_фото=0)["каталог"]
з = [о for о in кат if о.get("вовна_частка") is not None]
чужа = sum(1 for о in з if о["вовна_частка"] >= 0.5 and матеріал_речі(о)[0]
           and not any(k in матеріал_речі(о)[0] for k in ("вовн", "шерст", "wool")))
print("вовна_частка названа %d · =1.0 %d · основа без вовни, частка ≥0.5: N=%d"
      % (len(з), sum(о["вовна_частка"] == 1.0 for о in з), чужа))
