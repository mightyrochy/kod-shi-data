"""Рядок 186: мороз і сніг. Каталог_повний, сценарій «прогулянка містом, −8 °C, сніг» (реагенти НЕ
оголошені). (1) Замшеві/нубукові/велюрові взуття, сумки й рукавички з умовою K-WEA-05: ДО — код main
(`git show origin/main:джерела/аксесуари_погода.py`), ПІСЛЯ — поточний; і сухо при +16 °C (контроль).
(2) Пляжні й солом'яні сумки в пулі: ДО — нове відсічення вимкнено, ПІСЛЯ — увімкнено; `відсічено`.
Запуск із `джерела`: PYTHONPATH=. python3 проби/moroz_zamsha_186.py"""
import json, re, subprocess, sys, types; sys.path.insert(0, ".")
import bridge as B, аксесуари_погода as АП, міст_пакет as МП, пакет_моделі as ПМ
до = types.ModuleType("ап_до")
exec(subprocess.run(["git", "show", "origin/main:джерела/аксесуари_погода.py"], capture_output=True, text=True).stdout, до.__dict__)
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
сц = dict(вх["сценарій"], нагода="щоденне", місце="парк", темп_c=-8, опади="так", година=13, дрес_код="casual")
json.loads(B.виклик("запити", json.dumps(dict(вх, сценарій=сц), ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
замш = [c for c in кат.values() if c.get("слот") in ("взуття", "сумка", "рукавички") and АП.відмовляє_у_волозі(c)]
def з05(М, c, **п):
    return [з for з in М.сезон_і_погода([c], **п) if з["правило"] == "K-WEA-05"]
d, a = [c for c in замш if з05(до, c, темп_c=-8, опади="сніг")], [c for c in замш if з05(АП, c, темп_c=-8, опади="сніг")]
print("замша/нубук/велюр (взуття, сумки, рукавички) у каталозі: %d" % len(замш))
print("K-WEA-05 при −8 °C і снігу: ДО %d → ПІСЛЯ %d · з ручним «реагентів нема»: %d · сухо +16 °C: %d" % (
    len(d), len(a), sum(bool(з05(АП, c, темп_c=-8, опади="сніг", реагенти=0)) for c in замш),
    sum(bool(з05(АП, c, темп_c=16, опади=None)) for c in замш)))
if a:
    з = з05(АП, a[0], темп_c=-8, опади="сніг")[0]
    print("   приклад %s «%s»: %s · %s" % (a[0]["id"], a[0]["назва"][:50], з["суть"], з.get("чому", "")[-70:]))
ЛІТ, _ор = re.compile(r"пляжн|солом", re.I), ПМ._жорстке_відсічення
def _без(r, *а, **к):
    п = _ор(r, *а, **к)
    return None if п == "літня річ не для цієї температури" and r.get("слот") == "сумка" and ЛІТ.search(r.get("назва") or "") else п
літ = [c for c in кат.values() if c.get("слот") == "сумка" and ЛІТ.search(c.get("назва") or "")]
print("пляжних/солом'яних сумок у каталозі %d; проходять ворота пулу при −8 °C: ДО %d → ПІСЛЯ %d" % (len(літ),
      sum(not _без(c, -8) for c in літ), sum(not _ор(c, -8) for c in літ)))
for мітка, ф in (("ДО", _без), ("ПІСЛЯ", _ор)):
    ПМ._жорстке_відсічення = ф; МП._КЕШ_ПАКЕТА.clear()
    json.loads(B.виклик("запити", json.dumps(dict(вх, сценарій=сц), ensure_ascii=False)))
    пак = list(МП._КЕШ_ПАКЕТА.values())[-1]
    сумки = [c["id"] for c in пак["кандидати"].get("сумка", []) if ЛІТ.search(c.get("назва") or "")]
    print("%s: пляжних/солом'яних сумок у пулі %d %s · «літня річ…» у відсічено.лічба: %s" % (мітка, len(сумки), сумки,
          (пак.get("відсічено") or {}).get("лічба", {}).get("літня річ не для цієї температури", 0)))
