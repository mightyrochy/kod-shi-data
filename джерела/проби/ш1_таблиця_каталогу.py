"""Ш-1, PR 2: база каталогу з таблиці збирача — та сама до знака, і застаріла таблиця ловиться.

Будує таблицю (`таблиця_каталогу.зібрати` — сама звіряє відновлену з побудованою), кладе
її тимчасовим файлом «у вантаж» і міряє два шляхи продукту: базу на льоту
(`фід_каталог._прочитати_каталог`) і відновлення з таблиці (`таблиця_каталогу.база`,
разом зі звіркою ключа). Потім псує ключ двічі — змінений модуль побудови і файл даних,
якого при побудові не було, — таблиця мусить не вжитись і назвати, чому.
Запуск із теки `джерела` (потрібен розпакований каталог_повний.xml)."""
import copy, json, os, sys, tempfile, time
sys.path.insert(0, ".")
import feed as F, фід_каталог as ФК, фід_розбір as ФР, таблиця_каталогу as ТК

шлях = F.каталог_на_диску("каталог_повний.xml")
кеш = os.path.join(tempfile.mkdtemp(), "кеш.json")
json.dump({}, open(кеш, "w"))
т0 = time.time(); т = ТК.зібрати(шлях); с_зб = time.time() - т0
файл = os.path.join(tempfile.mkdtemp(), ТК.ІМ)
ТК.записати(т, файл)
ТК._таблиця_поруч = lambda тека: файл               # «у вантажі» — тимчасовий файл
т0 = time.time(); на_льоту = ФК._прочитати_каталог(шлях, 0, кеш, F.читати_збагачення()); с_л = time.time() - т0
ФР._ОФЕРИ_КЕШ.clear()
т0 = time.time(); р = ТК.база(шлях, 0, кеш); с_т = time.time() - т0
print("таблиця: %d записів, %d КБ gzip, модулів у ключі %d, даних %s · збудовано за %.1f с"
      % (len(т["записи"]), os.path.getsize(файл) // 1024, len(т["ключ"]["код"]),
         {ім: (м or "нема")[:8] for ім, м in sorted(т["ключ"]["дані"].items())}, с_зб))
print("база: на льоту %.1f с · з таблиці %.1f с (розбір фіду, звірка ключа, відновлення) · стан %s"
      % (с_л, с_т, ТК.СТАН.get("стан")))
print("з таблиці та сама база до знака (типи, кортежі, порядок ключів): %s · repr байт у байт: %s"
      % (р is not None and ТК.однакові(р[0], на_льоту), р is not None and repr(р[0]) == repr(на_льоту)))
for що, зіпсувати in (("змінено модуль фід_слот", lambda к: к["код"].update(фід_слот="0" * 32)),
                      ("файла даних при побудові не було", lambda к: к["дані"].update({"каталог_показ.json.gz": None}))):
    т2 = copy.deepcopy(т); зіпсувати(т2["ключ"]); ТК.записати(т2, файл)
    print("%s: вжито %s · стан %s · чому: %s"
          % (що, ТК.база(шлях, 0, кеш) is not None, ТК.СТАН.get("стан"), ТК.СТАН.get("чому")))
