# -*- coding: utf-8 -*-
"""Розбір 1/8 (вхід і сценарій): МОВНИЙ ШАР ВІДДАЄ ПАРСЕРУ `слова=""` — І ВСІ ГЕЙТИ ОПОРИ МОВЧАТЬ.
`мовний_шар.паспорт_з_шару` кличе той самий `паспорт_з_json`, але без її слів; читачі слів
(`сказано_про`, `місце_зі_слів`, `реєстри_зі_слів`, словник заперечень) на порожньому тексті
повертають «мовчу» = ПРОПУСКАЮ. Друкує кожен гейт на її тексті й на "" і те, що після шару
`паспорт.слова` порожнє, тож `міст_вхід` рядка «Її слова» не додає.
Запуск із теки `джерела`: `python3 проби/шлях_вхід_слова_шаром.py`."""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import паспорт_нагоди as ПН, мовний_шар as МШ

текст = "Збери образ під цю спідницю і чоботи для походу на концерт"
print("%-16s | %-34s | %s" % ("гейт опори", "на її тексті", 'на "" (шлях шару)'))
for поле in ("година", "темп_c", "тривалість_год", "формат"):
    print("сказано_про(%-14s) | %-34s | %s" % (поле, ПН.сказано_про(поле, текст), ПН.сказано_про(поле, "")))
for ключ in ("театр", "клуб", "офіс_корпоративний"):
    print("місце_зі_слів(%-13s) | %-34s | %s"
          % (ключ, "%s (опора: %s)" % (ПН.місце_зі_слів(ключ, текст), ", ".join(ПН.слова_місця(ключ))[:22]),
             ПН.місце_зі_слів(ключ, "")))
print("вето_поза_зонами_зі_слів   | %-34s | %s"
      % (json.dumps(ПН.вето_поза_зонами_зі_слів("без підборів і без принтів"), ensure_ascii=False)[:32],
         json.dumps(ПН.вето_поза_зонами_зі_слів(""), ensure_ascii=False)[:32]))

п = МШ.паспорт_з_шару({"event": {"free_text": "похід на концерт"}, "place": "office_corporate", "hour": 7,
                       "temperature_c": 30}, {}, None, None)["паспорт"]
print("\nшар віддав place=office_corporate, hour=7, temperature_c=30 БЕЗ жодної опори в тексті →"
      " паспорт: місце=%s година=%s темп_c=%s, не_взято_кодом=%s"
      % (п["місце"], п["година"], п["темп_c"], json.dumps(п.get("не_взято_кодом"), ensure_ascii=False)))
print("паспорт.слова=%r, перекладено_шаром=%s → `міст_вхід.py:305` («Її слова: «…»») не спрацьовує,"
      " і сирого речення не бачить жодна функціональна модель" % (п["слова"], п.get("перекладено_шаром")))
print("`показ.html:7661` безСлів = МОДЕЛЬ_МОВИ_П && паспорт.перекладено_шаром → канал `вимоги` теж порожній")
