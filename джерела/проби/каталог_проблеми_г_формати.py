# -*- coding: utf-8 -*-
"""Рядок 5624 (реєстр 5616, клас Г5): у кореневому каталозі — записи двох різних збирачів (складальник 07.09, якого
в репозиторії нема, і `виконавець.py` 18.09) з різними наборами полів. Факт: скільки записів кожного виду, які службові
поля є лише в одному виді й скільки комітів зробили каталог. Рядок 5651: каталог тепер складається з записів ОДНІЄЇ схеми v1 (`каталог_записи_v1.jsonl.gz`, `zhnyvarka/складальник.py`) — проба
першим рядком рахує форми запису й службові поля за схемою, а потім, як і раніше, походження оферів у XML.
Запуск: python3 джерела/проби/каталог_проблеми_г_формати.py"""
import collections, gzip, os, re, subprocess                                   # noqa: E401
К = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
xml = gzip.open(os.path.join(К, "каталог_повний.xml.gz"), "rt", encoding="utf-8").read()
ШЛЯХ_ЗАПИСІВ = os.path.join(К, "каталог_записи_v1.jsonl.gz")
if os.path.exists(ШЛЯХ_ЗАПИСІВ):
    import json
    з = [json.loads(р) for р in gzip.open(ШЛЯХ_ЗАПИСІВ, "rt", encoding="utf-8").read().split("\n") if р][1:]
    служб = {п[0] for r in з for п in r["параметри"] if п[2] == "с"}
    характ = {п[0] for r in з for п in r["параметри"] if п[2] == "к"}
    print("форм запису: %d (схема %s) · записів %d · службових полів різних %d · дослівних характеристик крамниці різних %d" % (
          len({r["схема"] for r in з}), "/".join(sorted({r["схема"] for r in з})), len(з), len(служб), len(характ)))
    print("походження (версія збирача, не формат): %s" % dict(collections.Counter(r["збирач"] for r in з)))
else:
    print("записів схеми v1 нема (каталог до 5651): форм запису — див. нижче, за наборами службових полів у XML")
ЗАПИСИ_Є = os.path.exists(ШЛЯХ_ЗАПИСІВ)
if not ЗАПИСИ_Є:        # до 5651: форми запису лишається рахувати за наборами службових полів у XML
    види = collections.defaultdict(list)
    for о in re.findall(r"<offer\b.*?</offer>", xml, re.S):
        поля = set(re.findall(r'<param name="([^"~][^"]*)"', о))
        види["складальник 07.09" if "бал_інформації" in поля else "виконавець 18.09" if "канал" in поля else "інше"].append(поля)
    частка = {в: collections.Counter(п for поля in з for п in поля) for в, з in види.items()}
    for в, з in види.items():
        print("%-18s %5d записів · службових полів (без «~») різних %d" % (в, len(з), len(частка[в])))
    а, б = list(частка)[:2]
    лише = lambda х, у: sorted(п for п, ч in частка[х].items() if ч >= 0.5 * len(види[х]) and not частка[у].get(п))  # noqa: E731
    print("поля в ≥50 %% записів «%s», яких нема в жодному «%s»: %s" % (а, б, лише(а, б)))
    print("поля в ≥50 %% записів «%s», яких нема в жодному «%s»: %s" % (б, а, лише(б, а)))
лог = subprocess.run(["git", "-C", К, "log", "--format=%ad %s", "--date=short", "--", "каталог_повний.xml.gz"],
                     capture_output=True, text=True).stdout.strip().splitlines()
print("комітів каталогу: %d (у неглибокому клоні — неповно) · перший: %s" % (len(лог), лог[-1] if лог else "—"))
print("складальник у репозиторії: %s" % ("є, zhnyvarka/складальник.py (каталог = функція записів v1)" if ЗАПИСИ_Є else
      "нема (так каже влиття_в_каталог.py)" if "якого в репозиторії НЕМА" in
      open(os.path.join(К, "zhnyvarka", "влиття_в_каталог.py"), encoding="utf-8").read() else "див. влиття_в_каталог.py"))
