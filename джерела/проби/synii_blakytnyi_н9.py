# -*- coding: utf-8 -*-
"""Н9: скількох речей каталогу торкнеться поділ сім'ї «синя» на синю й блакитну — ЛІЧБА перед
нарядом, словник не чіпано. Звіт Research §3: слова окремі, але `verify.СІМ_Ї_СЛІВ["синя"]` зводить
синє й блакитне в ОДНУ сім'ю, тож у спорі назви з виміром («сусід_сім_ї») і у звірці кадрів
(`фід_кадр_колір`: «власний вимір кадру мусить назвати колір ТІЄЇ Ж сім'ї, що слово крамниці»)
блакитний і синій завжди «згодні». Друкує на `каталог_збагачення`: скільки речей сім'ї має слово
крамниці й вимір по РІЗНІ боки поділу — саме вони змінять відповідь. З теки `джерела`:
`python3 проби/synii_blakytnyi_н9.py`."""
import sys, collections
sys.path.insert(0, ".")
import feed, verify as V, colorspace as cs, фід_розбір as ФР
СИНЯ = ("синій", "темно-синій", "джинсовий", "петроль", "електрик")     # поділ на пробу, не в коді
БЛАКИТНА = ("блакитний", "бірюзовий")
бік = lambda с: "синя" if с in СИНЯ else "блакитна" if с in БЛАКИТНА else None
зб = feed.читати_збагачення()
пари, сусіди, всього = collections.Counter(), collections.Counter(), 0
for o in ФР.читати_yml("каталог_повний.xml")[0]:
    z = зб.get(o["id"]) or {}
    к = z.get("колір_основний") or {}
    сл_в = к.get("слово")
    сл_к = (V.слово_крамниці(" ".join(str(o.get("колір_сирий") or "").lower().split())) or {}).get("ім")
    if not к.get("hex") or V.сім_я_слова(сл_в) != "синя":
        continue
    всього += 1
    r = V.перевірити(cs.hx(к["hex"]), назва=сл_в)
    if r.get("сусід_сім_ї"):
        сусіди[(сл_в, r["сусід_сім_ї"], "різні боки" if бік(сл_в) != бік(r["сусід_сім_ї"]) else "той самий бік")] += 1
    if бік(сл_к) and бік(сл_в):
        пари[(бік(сл_к), бік(сл_в))] += 1
print("слова сім'ї «синя» в лексиконі: %s" % (V.СІМ_Ї_СЛІВ["синя"],))
print("проба поділу: синя %s · блакитна %s" % (СИНЯ, БЛАКИТНА))
print("речей із виміром, чиє слово в сім'ї «синя»: %d" % всього)
print("слово крамниці × вимір по боках поділу: %s" % dict(sorted(пари.items())))
print("спір назви й виміру («сусід_сім_ї») у цій сім'ї: %s" % dict(sorted(сусіди.items())))
print("ЗМІНЯТЬ ВІДПОВІДЬ: %d речей (пари з різних боків) + %d спорів через межу"
      % (sum(v for (a, b), v in пари.items() if a != b),
         sum(v for (_a, _b, м), v in сусіди.items() if м == "різні боки")))
print("synii_blakytnyi_н9: зелено (лічба, не гейт)")
