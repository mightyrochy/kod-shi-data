# -*- coding: utf-8 -*-
"""Корінь Е2-втрата-слова, п.2(б): плитки її екрана «Вітер» і «Реагенти на дорогах» у стані помічниці. Показ шле
поля форми (`станДляШі` → `зібратиВхід().сценарій`: `вітер_бал` 0/1/2, `реагенти` 0/1), міст `помічниця` кладе їх у
`state.case.fields` дротом випадку (`дріт_моделі.випадок`). ДО плитки поза `ПОЛЯ_ВИПАДКУ` губились мовчки; ПІСЛЯ —
`wind_band` (смуга за балом, `сценарій.смуга_з_бала`) і `road_salt` (`сценарій.сіль_на_дорозі`), «нема» — теж її
слово. Ще — випадок рук із днем: ті самі поля, коли їх несе `day`, двічі не їдуть. Моделі не кличе.
Запуск: cd джерела && python3 проби/е2_втрата_слова_п2б.py"""
import json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import міст_помічниця as МП, дріт_моделі as Д, сценарій as С
for підпис, плитки in (("сильний вітер, реагенти є", {"вітер_бал": 2, "реагенти": 1}),
                       ("безвітря, реагентів нема", {"вітер_бал": 0, "реагенти": 0}),
                       ("плиток не торкалась", {})):
    поля = dict({"нагода": "робота", "смуга_погоди": "frost", "опади": "сніг"}, **плитки)
    п = json.loads(МП.помічниця({"питання": "чи взяти замшеві чоботи?", "довідка": "APP",
                                   "стан": {"екран": "сценарій", "сценарій": {"поля": поля}}}))["промпт"]; п = json.loads(п) if isinstance(п, str) else п
    ф = п["state"]["case"]["fields"]
    print("%-28s fields: %s" % (підпис, json.dumps({к: ф.get(к) for к in ("weather_band", "wind_band", "road_salt",
                                                                       "precipitation")}, ensure_ascii=False)))
сц = {"смуга_погоди": "frost", "опади": "сніг", "смуга_вітру": "strong", "реагенти": 1}
день = С.день_кодами(сц)
в = Д.випадок(dict(сц, подія="робота"), день)
print("з днем: day %s · case %s" % ({к: день.get(к) for к in ("wind_band", "road_salt")},
                                   {к: в.get(к) for к in ("wind_band", "road_salt")}))
