"""Ф-9 (звіт Research П1; рядок 84 відкрито власником лише для довжини проти зросту):
довжина виробу в см + точка виміру → поділ на ЦЬОМУ тілі → клас довжини. Друкує
покриття поля по слотах і те, як клас поділу й розбіг зі словом міняються зі зростом.
Запуск із теки `джерела`: `python3 проби/ф9_довжина_зріст.py`."""
import os, sys, collections
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as ФК, fit as ПС, композитор_річ as КР

кат = ФК._прочитати_каталог(feed.каталог_на_диску(), ліміт_фото=0)["каталог"]
є = [r for r in кат if r.get("довжина_виробу_см") is not None]
сл, вс = collections.Counter(r["слот"] for r in є), collections.Counter(r["слот"] for r in кат)
print("ПОКРИТТЯ `довжина_виробу_см` (каталог %d речей): %d (%.1f %%); точка виміру %s"
      % (len(кат), len(є), 100.0 * len(є) / len(кат),
         dict(collections.Counter(r["довжина_виробу_точка"] for r in є))))
for с in sorted(сл, key=lambda x: -сл[x]):
    print("   %-12s %4d із %4d (%.1f %%)" % (с, сл[с], вс[с], 100.0 * сл[с] / вс[с]))

print("\nКЛАС ПОДІЛУ НА ТРЬОХ ЗРОСТАХ (той самий каталог, ті самі речі)")
print("   ДО (слово довжини, одне на всі зрости): %s · слова нема в %d речах"
      % (dict(collections.Counter(r["довжина_рівень"] for r in є if r.get("довжина_рівень")).most_common()),
         sum(1 for r in є if not r.get("довжина_рівень"))))
for зріст in (155, 165, 175):
    т = ПС.тіло(зріст, {"плечі": 92, "груди": 90, "талія": 72, "стегна": 100})
    класи, лічба = collections.Counter(), collections.Counter()
    for r in є:
        р = КР._у_річ(r, r["слот"], т)
        if р.get("край_джерело") != "виріб":
            лічба["число не з цієї речі"] += 1; continue
        класи[р["довжина_клас_виміряний"]] += 1
        лічба["довша за тіло"] += bool(р.get("довжина_надлишок_см"))
        лічба["поділ між класами"] += bool(р.get("довжина_клас_між"))
        лічба["знахідок розбігу"] += sum(1 for з in ПС.довжина_проти_зросту(т, [р])
                                        if "слово" in з["суть"])
    print("   зріст %d: %s" % (зріст, dict(класи.most_common())))
    print("      %s" % dict(лічба))

print("\nОДНА РІЧ, ТРИ ЗРОСТИ (сукня 94 см від плечей, слово крамниці «литка»):")
річ = dict(id="с-1", слот="сукня", довжина_виробу_см=94.0, довжина_виробу_точка="плечі",
           довжина_виробу_розкид_см=2.0, довжина_рівень="литка", довжина_джерело="param довжина")
for зріст in (155, 165, 175):
    т = ПС.тіло(зріст, {"плечі": 92, "груди": 90, "талія": 72, "стегна": 100})
    р = КР._у_річ(річ, "сукня", т); зн = ПС.довжина_проти_зросту(т, [р])
    print("   %d см → поділ %.1f см · клас «%s» (відступ %s, між класами %s) · %s"
          % (зріст, р["низ_см"], р["довжина_клас_виміряний"], р["довжина_клас_відступ_см"],
             р["довжина_клас_між"],
             "; ".join("%s %s сила_нп %.2f" % (з["суть"][:46], з["регістр"], з["сила_нп"])
                       for з in зн) or "знахідок нема"))
