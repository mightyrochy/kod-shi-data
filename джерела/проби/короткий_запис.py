# -*- coding: utf-8 -*-
"""К-3: скільки важить річ пулу повним і коротким записом і скільки їх влазить у бюджет.

Один пул стенда двома записами (`каталог_коди`, `дріт_моделі.річ(короткий=True)`) при тому самому
бюджеті 120 000; заглушка розбору — `аудит/проби/заглушка_розбору.py` (коди живого прогону Н-1).
Прогін: python3 проби/короткий_запис.py     (~3 хв: заглушка + два повні збирання)
"""
import json, os, statistics as st, sys, tempfile
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path[:0] = [ТУТ, os.path.join(ТУТ, "..", "аудит", "проби")]; os.chdir(ТУТ)
import feed as Ф, bridge as B, міст_пакет as МП, дріт_моделі as Д, каталог_коди as КК
import заглушка_розбору as ЗР            # заглушка файла розбору: без неї міряти нема на чому
ФАЙЛ = os.path.join(tempfile.gettempdir(), КК.РОЗБІР_ІМ + ".gz")
os.environ["ROZBIR_KODY"] = os.environ.get("ROZBIR_KODY") or ЗР.зібрати(ФАЙЛ)[0]
ВХ = dict(json.load(open("стенд_вх.json", encoding="utf-8")), каталог=Ф.каталог_на_диску())
д = lambda o: len(json.dumps(o, ensure_ascii=False, separators=(",", ":")))

def пул(короткий):
    """(речі, символів тексту пакета, поле `запис`) одного повного збирання."""
    КК.оголосити(короткий); МП._КЕШ_ПАКЕТА.clear()
    json.loads(B.виклик("запити", json.dumps(dict(ВХ, короткий_запис=короткий), ensure_ascii=False)))
    п = [p for p in МП._КЕШ_ПАКЕТА.values() if p.get("пакет")][0]
    return [r for рч in п["пакет"]["пул"].values() for r in рч], len(п["текст"]), п.get("запис")
повні, симв_п, _ = пул(False)
короткі, симв_к, запис = пул(True)
без = lambda r: {к: v for к, v in r.items() if к != "features"}
print("вимкнено: пул %d речей, пакет %d симв., полів розбору в записі %d · увімкнено: %s"
      % (len(повні), симв_п, sum(1 for r in повні if r.get("features") or r.get("розбір")), запис))
for ім, сп in (("повний як сьогодні", [д(Д.річ(r)) for r in повні]),
               ("короткий без features", [д(Д.річ(без(r), короткий=True)) for r in короткі]),
               ("короткий з features", [д(Д.річ(r, короткий=True)) for r in короткі])):
    print("  %-22s симв./річ: медіана %3d, середнє %5.1f" % (ім, st.median(сп), sum(сп) / len(сп)))
повн_з = [Д.річ(r) for r in короткі]      # ті самі речі ПОВНИМ записом — суд, ремонт, опис
print("  рядок особливостей: медіана %d симв. (приклад власника — 73); не збіднювати судження: "
      "зі словом крамниці %d з %d, з особливостями %d з %d"
      % (st.median([len(r.get("features") or "") for r in короткі]),
         sum(1 for o in повн_з if o.get("name")), len(повн_з),
         sum(1 for o in повн_з if o.get("features")), len(повн_з)))
print("РЕЧЕЙ У БЮДЖЕТІ 120 000: повний %d (%d симв.) → короткий %d (%d симв.) = %+.0f %%"
      % (len(повні), симв_п, len(короткі), симв_к, 100.0 * len(короткі) / len(повні) - 100))
