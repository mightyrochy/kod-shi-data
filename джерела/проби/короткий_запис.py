# -*- coding: utf-8 -*-
"""К-3: скільки важить річ пулу повним і коротким записом і скільки їх влазить у бюджет.

Один пул стенда двома записами (`каталог_коди`, `дріт_моделі.річ(короткий=True)`) при тому самому
бюджеті 120 000; заглушка розбору — `аудит/проби/заглушка_розбору.py` (коди живого прогону Н-1).
Прогін: python3 проби/короткий_запис.py     (~3 хв: заглушка + два повні збирання)
"""
import json, os, statistics as st, sys, tempfile
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path[:0] = [ТУТ, os.path.join(ТУТ, "..", "аудит", "проби")]; os.chdir(ТУТ)
import feed as Ф, bridge as B, міст_пакет as МП, дріт_моделі as Д, каталог_коди as КК, каталог_розбір as КР
import заглушка_розбору as ЗР            # заглушка файла розбору: без неї міряти нема на чому
ФАЙЛ = os.path.join(tempfile.gettempdir(), КК.РОЗБІР_ІМ + ".gz")
os.environ["ROZBIR_KODY"] = os.environ.get("ROZBIR_KODY") or ЗР.зібрати(ФАЙЛ)[0]
ВХ = dict(json.load(open("стенд_вх.json", encoding="utf-8")), каталог=Ф.каталог_на_диску())
д = lambda o: len(json.dumps(o, ensure_ascii=False, separators=(",", ":")))

def пул(короткий):
    """(речі, символів тексту пакета, поле `запис`) одного повного збирання."""
    КК.оголосити(короткий); МП._КЕШ_ПАКЕТА.clear()
    json.loads(B.виклик("запити", json.dumps(dict(ВХ, короткий_запис=короткий), ensure_ascii=False)))
    п = [p for p in МП._КЕШ_ПАКЕТА.values() if p.get("пакет")][0]
    return [r for рч in п["пакет"]["пул"].values() for r in рч], len(п["текст"]), п.get("запис")
повні, симв_п, _ = пул(False)
короткі, симв_к, запис = пул(True)
# «без features» МІРЯЄТЬСЯ НА ГОТОВОМУ ЗАПИСІ, а не на речі без рядка: знятий з РЕЧІ рядок
# повернув би в запис назву крамниці (слова крамниці йдуть геть лише разом із заміною), і
# число казало б не те, що питають. Питають: скільки важить сам рядок особливостей.
без = lambda o: {к: v for к, v in o.items() if к != Д.КОРОТКІ_КЛЮЧІ["features"]}
print("вимкнено: пул %d речей, пакет %d симв., полів розбору в записі %d · увімкнено: %s"
      % (len(повні), симв_п, sum(1 for r in повні if r.get("features") or r.get("розбір")), запис))
МІРИ = (("повний ДО", [д(Д.річ(r)) for r in повні]),
        ("повний ПІСЛЯ", [д(Д.річ(r, пул=True)) for r in повні]),
        ("короткий ДО", [д(Д.річ(r, короткий=True)) for r in короткі]),
        ("короткий ПІСЛЯ", [д(Д.річ(r, короткий=True, пул=True)) for r in короткі]),
        ("короткий без features", [д(без(Д.річ(r, короткий=True))) for r in короткі]),
        ("короткий з features", [д(Д.річ(r, короткий=True)) for r in короткі]))
сер = lambda сп: sum(сп) / len(сп)
for ім, сп in МІРИ:
    print("  %-22s симв./річ: медіана %3d, середнє %5.1f" % (ім, st.median(сп), сер(сп)))
повн_з = [Д.річ(r) for r in короткі]      # ті самі речі ПОВНИМ записом — суд, ремонт, опис
пари = {"%s/%s" % (к, зв): sum(1 for r in короткі if (r.get("розбір") or {}).get(зв)
                              not in (None, "", [], {}) and Д.річ(r).get(к) not in (None, "", [], {}))
        for к, зв in list(Д._ЗАМІНЕНІ_РОЗБОРОМ.items()) + list(Д._ЗАЙВІ_ПРИ_КОДІ.items())[::-1]}
дір = [[Д.КОРОТКІ_КЛЮЧІ.get(к, к) for к, зв in Д._ЗАМІНЕНІ_РОЗБОРОМ.items()
        if Д.КОРОТКІ_КЛЮЧІ.get(к, к) in Д.річ(r, короткий=True)
        and (r.get("розбір") or {}).get(зв) in (None, "", [], {})] for r in короткі]
print("  попарно (поле коду / поле розбору кажуть те саме): %s — у записі лишається одне"
      % ", ".join("%s %d" % (п, н) for п, н in sorted(пари.items(), key=lambda х: -х[1]) if н))
print("  рядок особливостей: медіана %d симв. (приклад власника — 73); не збіднювати судження: "
      "зі словом крамниці %d з %d, з особливостями %d з %d"
      % (st.median([len(r.get("features") or "") for r in короткі]),
         sum(1 for o in повн_з if o.get("name")), len(повн_з),
         sum(1 for o in повн_з if o.get("features")), len(повн_з)))
print("  дір розбору (поле коду лишилось, бо розбір його не закрив): %.1f поля на річ, %.0f симв./річ "
      "— на стільки коротшим був би запис при ПОВНОМУ розборі" % (
          sum(len(д_) for д_ in дір) / len(дір),
          sum(д(Д.річ(r, короткий=True)) - д({к: v for к, v in Д.річ(r, короткий=True).items() if к not in д_})
              for r, д_ in zip(короткі, дір)) / len(дір)))
_кор = [Д.річ(r, короткий=True) for r in короткі]
_кл = Д.КОРОТКІ_КЛЮЧІ
print("  КОЛІР РІВНО РАЗ (§5): речей із виміром і словом разом %d; назва від розбору в записі %d; "
      "спорів «слово проти виміру» %d — вимір лишається кольором, слово стоїть позначкою"
      % (sum(1 for o in _кор if o.get(_кл["hex"]) and o.get(_кл["color"])),
         sum(1 for o in _кор if "color_main" in o),
         sum(1 for o in _кор if o.get(_кл["color_disputed"]))))
print("  СТЕЛЯ РЯДКА ОСОБЛИВОСТЕЙ: короткий запис коротший за теперішній, поки рядок ≤ %.0f симв. "
      "(зараз %.0f; стеля `каталог_розбір.СТЕЛЯ_СЛІВ` = %d слів)"
      % (max(0.0, сер(МІРИ[0][1]) - сер(МІРИ[4][1])),
         сер([len(r.get("features") or "") for r in короткі]), КР.СТЕЛЯ_СЛІВ))
print("РЕЧЕЙ У БЮДЖЕТІ 120 000: повний %d (%d симв.) → короткий %d (%d симв.) = %+.0f %%"
      % (len(повні), симв_п, len(короткі), симв_к, 100.0 * len(короткі) / len(повні) - 100))
