# -*- coding: utf-8 -*-
"""K-PRC-01 (ціна ÷ комбінаторний обхват) і K-PRC-02 (ремонтопридатність) — вісь
доїхала до РЕЧІ, а не лишилась самозвітом про метрику.

ДО ПРАВКИ: `ціна_за_обхват` кликалась один раз на прогін і віддавала рядок
«вісь розрізняє кандидатів / вісь вироджена». Жодна річ свого числа не несла, тож
ані суд, ані жінка його не бачили: дві сумки в одному образі були для правила
нерозрізненні. K-PRC-02 жив полем усередині того самого звіту.
ПІСЛЯ: кожна річ пулу несе `ціна_ранг` — частку речей СВОГО слота, що на образ
коштують дешевше, — і річ із верхньої чверті дістає рядок вердикту. K-PRC-02
стоїть окремо від рангу: конструкцію низу називають 6 пар із 2 096, і жодна з них
цього прогону в пул не проходить."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
ц = з["цінність"]
print("вісь: обхват %s–%s · розкид %s · вироджена=%s · рангів у рядках речей %d"
      % (ц["обхват_мін"], ц["обхват_макс"], ц["відносний_розкид"], ц["вироджена"], ц["рангів"]))
пак = [p for p in B._КЕШ_ПАКЕТА.values() if p.get("_цінність", {}).get("є")][0]
кат = {c["id"]: c for c in пак["_каталог"]}
пул = [кат[r["id"]] for п in з["кандидати"].values() for r in п if r["id"] in кат]
дорога = max([c for c in пул if c.get("ціна_ранг") is not None and c["слот"] == "сукня"],
             key=lambda c: c["ціна_ранг"])
взут = next(c for c in пул if c["слот"] == "взуття")
клеєна = next(c for c in пак["_каталог"] if c.get("ремонтопридатна") is False)
судити = lambda ід: {z["правило"]: z for z in
    (((json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False))
       ).get("вердикт") or {}).get("образи") or [{}])[0].get("знахідки") or [])}
з1 = судити([дорога["id"], взут["id"]])
print("K-PRC-01:", "%s %.2f · %s" % (з1["K-PRC-01"]["сила"], з1["K-PRC-01"]["сила_нп"],
                                     з1["K-PRC-01"]["суть"][:84]))
з2 = судити([дорога["id"], клеєна["id"]])
print("K-PRC-02:", "%s %.2f · %s" % (з2["K-PRC-02"]["сила"], з2["K-PRC-02"]["сила_нп"],
                                     з2["K-PRC-02"]["суть"][:84]))
дешева = min([c for c in пул if c.get("ціна_ранг") is not None and c["слот"] == "сукня"],
             key=lambda c: c["ціна_ранг"])
print("дешева за образ (ранг %.2f) → K-PRC-01:" % дешева["ціна_ранг"],
      "нема (правило мовчить законно)" if "K-PRC-01" not in судити([дешева["id"], взут["id"]])
      else "Є — а мусило мовчати")
assert "K-PRC-01" in з1 and "K-PRC-02" in з2
