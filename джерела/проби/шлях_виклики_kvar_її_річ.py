"""Розбір шляху 4/8 · K-VAR-01 прогону («та сама річ у двох картках») і її закріплена річ. Руки 1 і 2 обидві
мусять нести її річ з фото (закріплення коду) і обидві взяли той самий кардиган (так у прогоні власника 4123:
ж-08489@sunwin-store.com у руках 1 і 2). Друкує, що повертає `повнота_образу.повтор_прогону` (правило повертає
щонайбільше ОДИН, перший повтор), і що стоїть у записах рук 1–2 файлу власника 2012 (виклики → k_var_01_прогону).
Запуск: cd джерела && python3 проби/шлях_виклики_kvar_її_річ.py"""
import json, os, sys
тут = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(тут))
import повнота_образу as ПО
її = dict(id="її-ф1", назва="спідниця міні під рептилію", слот="низ")
кардиган = dict(id="ж-08489@sunwin-store.com", назва="Кардиган жіночий вовняний на запах із поясом", слот="верх")
реєстр = {}
р1 = [dict(id="ж-02598@sunwin-store.com", назва="Джемпер щільний", слот="верх"), її, кардиган, dict(id="ж-10666@cooshwear.com", назва="Чоботи LISS", слот="взуття")]
р2 = [її, кардиган, dict(id="ж-00001@kosiv.ua", назва="Ковбойки KOSIV", слот="взуття")]
print("рука 1 першою: %s" % ПО.повтор_прогону(реєстр, "1", р1))
з = ПО.повтор_прогону(реєстр, "2", р2)
print("рука 2 (її річ + той самий кардиган): %s → речі %s" % (з and з.get("суть"), з and з.get("речі")))
чистий = {}
ПО.повтор_прогону(чистий, "1", [x for x in р1 if x is not її])
print("ті самі руки без її речі: %s" % (ПО.повтор_прогону(чистий, "2", [x for x in р2 if x is not її]) or {}).get("суть"))
д = json.load(open(os.path.join(тут, "../../аудит/тести/власник_2026-09-25/verdykty-0phxvk-2026-09-25-2012.json"), encoding="utf-8"))
for і, п in enumerate(д["прогони"]):
    for в in п["вердикти"]:
        if в.get("рука") not in ("1", "2"): continue
        к = [x.get("k_var_01_прогону") for x in (в.get("етапи") or {}).get("виклики") or [] if x.get("k_var_01_прогону")]
        if к: print("файл 2012 · прогін %d · рука %s: K-VAR-01 на %d з %d викликів — «%s», речі %s"
                    % (і, в["рука"], len(к), len(в["етапи"]["виклики"]), к[-1]["суть"], к[-1]["речі"]))
