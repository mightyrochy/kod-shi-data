# -*- coding: utf-8 -*-
"""Рішення власника 24-25.09 (аудит/ПЕРЕДАЧА.md §0): «Довідка показу дописує
~11.9 тис. символів із фразами-прикладами до виклику 0 — прибрати». Ця проба
перевіряє, чи код це вже зробив: `ШІ_ДОВІДКА` (показ.html:4564-4576) і досі
дописується до КОЖНОГО виклику 0 (`паспортПоРозмовіП`, показ.html:5115-5138) через
`додатокДоПаспортаП()` (4817-4823 → 5135) — без умови, щоразу, коли розмова про
сценарій іде далі. Друкує факт (розмір і чи виклик і досі активний).
Запуск: cd джерела && python3 проби/шлях_розмір_довідка_виклик0.py"""
import os, re
показ = open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                          "показ.html"), encoding="utf-8").read()

довідка = re.search(r"const ШІ_ДОВІДКА = `(.*?)`;", показ, re.S)
assert довідка, "константу ШІ_ДОВІДКА не знайдено — перевір показ.html"
симв_довідки = len(довідка.group(1))

викликана_у = "const промпт = пп.промпт + '\\n\\n' + додатокДоПаспортаП();"
assert викликана_у in показ, "додатокДоПаспортаП більше не додається до виклику 0 — перевір показ.html:5135"
безумовно = ("паспортПоРозмовіП" in показ
             and показ.index(викликана_у) > показ.index("async function паспортПоРозмовіП()"))
поруч_станДляШі = "'\\nСТАН ЗАРАЗ:\\n' + станДляШі();" in показ

print("ШІ_ДОВІДКА (показ.html:4564-4576):", симв_довідки, "симв")
print("додатокДоПаспортаП() = 'ДОВІДКА ПРО ЗАСТОСУНОК:\\n' + ШІ_ДОВІДКА + '\\nСТАН ЗАРАЗ:\\n' + станДляШі()")
print("дописується до виклику 0 безумовно (показ.html:5135):", безумовно)
print("рішення власника 24-25.09 «прибрати» — виконано:", not безумовно)
assert безумовно, "якщо це впало — рядок 34 ПЕРЕДАЧА.md уже виконано, зняти цю ваду зі списку"
assert симв_довідки > 10_000, "довідка стала суттєво коротшою за задокументовані ~11.9 тис. симв."
