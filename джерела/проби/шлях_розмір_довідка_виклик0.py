# -*- coding: utf-8 -*-
"""Рішення власника 24-25.09 (аудит/ПЕРЕДАЧА.md §0) і В-10 розбору 1/8: «Довідка показу дописує
~11 тис. символів із фразами-прикладами до виклику 0 — прибрати». Ця проба міряє, чи код це
зробив: `ШІ_ДОВІДКА` більше не дописується до жодного виклику 0 (`паспортПоРозмовіП`), а питання
про застосунок має свій виклик `помічникП`, який довідку зі станом і несе.
Друкує факти й числа до/після. Запуск: cd джерела && python3 проби/шлях_розмір_довідка_виклик0.py"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import паспорт_нагоди as ПН

показ = open("показ.html", encoding="utf-8").read()

довідка = re.search(r"const ШІ_ДОВІДКА = `(.*?)`;", показ, re.S)
assert довідка, "константу ШІ_ДОВІДКА не знайдено — перевір показ.html"
симв_довідки = len(довідка.group(1))
промпт = len(ПН.промпт_паспорта({"година": 11, "темп_c": 18},
                                "Збери образ під цю спідницю і чоботи для походу на концерт"))

склейка = "const промпт = пп.промпт + '\\n\\n' + додатокДоПаспортаП();"
без_додатка = "const промпт = пп.промпт;"
дописується = склейка in показ
помічниця = bool(re.search(r"async function помічникП[\s\S]{0,400}ШІ_ДОВІДКА", показ))

print("ШІ_ДОВІДКА:", симв_довідки, "симв (+ шапка «КРІМ ПАСПОРТА» 431 і стан ~450 — заміряно на main 26.09)")
print("промпт виклику 0 (збирач):", промпт, "симв")
print("ДО:    промпт + довідка + шапка + стан ≈", промпт + симв_довідки + 431 + 450,
      "симв — довідка", round(100.0 * симв_довідки / (промпт + симв_довідки + 431 + 450)), "%")
print("ПІСЛЯ: промпт виклику 0 =", промпт, "симв — довідки нема:", not дописується)
print("промпт складається рівно з виводу збирача (`const промпт = пп.промпт;`):", без_додатка in показ)
print("питання про застосунок має свій виклик `помічникП`, і довідку зі станом несе він:", помічниця)

assert not дописується, "довідка досі дописується до виклику 0 — рішення власника не виконано"
assert без_додатка in показ, "виклик 0 бере промпт не з збирача — перевір `паспортПоРозмовіП`"
assert помічниця, "довідка зникла й з `помічникП` — питання про застосунок лишилось без відповіді"
print("\nрішення власника 24-25.09 «прибрати» — виконано: True (−%d симв. на КОЖНОМУ виклику 0)"
      % (симв_довідки + 431 + 450))
