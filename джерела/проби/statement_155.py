# -*- coding: utf-8 -*-
"""Рядок 155: чи валить добуток слотів збирання в браузері — 6 сцен × усі наміри.
Продукт іде в Pyodide (32-бітний WASM), де `len(range(N))` мусить влізти в `Py_ssize_t` =
2³¹−1, а `random.sample` перше кличе саме `len`; у CPython він 64-бітний, тож CI цього не
бачить НІКОЛИ — межа емулюється підміною `random.Random.sample`. Кожен виклик вибірки
міряється двічі: «ДО» — старим рядком, «ПІСЛЯ» — нинішнім відбором.
Запуск: PYTHONPATH=. python3 проби/statement_155.py"""
import json, os, random, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, стенд_знімок as С, композитор_оцінка as КО, реєстр_намір as РН
МЕЖА, справжній, НАМІРИ = 2**31 - 1, random.Random.sample, sorted(РН.INTENT)
def тридцятидвобітний(self, population, k, **kw):   # так поводиться Pyodide, і лише він
    if len(population) > МЕЖА: raise OverflowError("Python int too large to convert to C ssize_t")
    return справжній(self, population, k, **kw)
random.Random.sample = тридцятидвобітний
старий, найбільше, падіння, справжня_вибірка = (lambda N, k, с: sorted(
    random.Random(с).sample(range(N), k))), {}, {"ДО": [], "ПІСЛЯ": []}, КО._вибірка_індексів
def під_наглядом(усього, скільки, сід):
    """Той самий відбір, але спершу міряє, чи впав би на ньому старий рядок."""
    найбільше[сцена] = max(найбільше.get(сцена, 0), усього)
    try: старий(усього, скільки, сід)
    except OverflowError: падіння["ДО"].append((сцена, намір, усього))
    return справжня_вибірка(усього, скільки, сід)
КО._вибірка_індексів = під_наглядом
for сцена, опис in С.СЦЕНАРІЇ.items():
  for намір in НАМІРИ:
    вх = json.load(open("стенд_вх.json"))
    вх["сценарій"], вх["випадок"], вх["намір"] = dict(опис, намір=намір), сцена, намір
    try: r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False))).get("помилка")
    except Exception as e: r = "%s: %s" % (type(e).__name__, e)   # виняток — теж падіння
    if r: падіння["ПІСЛЯ"].append((сцена, намір, str(r)[:60]))
print("сцен %d × намірів %d = %d прогонів · 32-бітну межу %d емульовано\n"
      "ПАДІНЬ (викликів вибірки над межею): ДО %d · ПІСЛЯ %d" % (len(С.СЦЕНАРІЇ), len(НАМІРИ),
      len(С.СЦЕНАРІЇ) * len(НАМІРИ), МЕЖА, len(падіння["ДО"]), len(падіння["ПІСЛЯ"])))
for н, к in ((н, len({с for с, x, _ in падіння["ДО"] if x == н})) for н in НАМІРИ):
    print("  %-16s ДО впало на %d сценах із %d %s" % (н, к, len(С.СЦЕНАРІЇ),
          "← сміливий намір тримає більше слотів живими" if к else ""))
for с in С.СЦЕНАРІЇ: print("  %-22s найбільший добуток %.2e %s" % (с, найбільше.get(с, 0),
    "— понад межу" if найбільше.get(с, 0) > МЕЖА else ""))
