# -*- coding: utf-8 -*-
# Рядки 202, 203 (Л-19). ФАКТ трьома числами: (203) чи `почистити` — НЕРУХОМА ТОЧКА для
# ланцюга чистки каталогу, тобто чи `почистити(артикул→літера→код(n))` дає те саме, що
# `почистити(n)`, по крамницях; (203) суд крамниці про коди КОЛЬОРУ; (202) код моделі в
# голові `param опис` — у СИРОМУ архіві й у ЧИСТОМУ каталозі. Числа «до» — у тілі PR.
import os, sys, gzip, shutil, collections
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed, назва_речі as НР, чистка_каталогу as ЧК
чистий = sys.argv[1] if len(sys.argv) > 1 else feed.каталог_на_диску()
архів = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
    os.path.dirname(чистий), os.pardir, "каталог_повний.xml.gz")
сирий = os.path.join(os.path.dirname(os.path.abspath(чистий)), "_л19_сирий.xml")
with gzip.open(архів, "rb") as вх, open(сирий, "wb") as вих:
    shutil.copyfileobj(вх, вих)
сирі = feed.читати_yml(сирий)[0]
os.remove(сирий)
по = collections.defaultdict(list)
for o in сирі:
    по[ЧК._крамниця(o)].append(НР.розкодувати(str(o.get("назва") or "")))
коди, кольори, розх = {}, {}, collections.Counter()
for кр, назви in по.items():
    коди[кр] = НР.коди_моделі([НР.почистити(н) for н in назви])
    кольори[кр] = НР.коди_кольору(назви)
    _ч = lambda н: НР.почистити(н, коди[кр], кольори[кр])
    for н in назви:
        if _ч(н) != _ч(НР.зняти_код_моделі(НР.зняти_літеру_моделі(НР.зняти_артикул(н)), коди[кр])):
            розх[кр] += 1
print("РЯДОК 203 — `почистити` НЕ нерухома точка для ланцюга каталогу: %d назв із %d %s"
      % (sum(розх.values()), len(сирі), dict(розх) or "—"))
print("РЯДОК 203 — суд крамниці про коди КОЛЬОРУ (поріг %d токени): крамниць %d %s"
      % (НР.МІН_ТОКЕНІВ_КОЛЬОРУ, sum(1 for к in кольори.values() if к),
         {к: len(v) for к, v in sorted(кольори.items()) if v} or "—"))
def з_кодом_в_описі(набір):
    c = collections.Counter()
    for o in набір:
        у_назві = set(ЧК._ЛАТИНСЬКЕ_СЛОВО.findall(str(o.get("назва") or ""))) & set(коди.get(ЧК._крамниця(o)) or ())
        if у_назві & set(str((o.get("параметри") or {}).get(ЧК.ПАРАМ_ОПИСУ) or "").split()[:ЧК.ГОЛОВА_ОПИСУ]):
            c[ЧК._крамниця(o)] += 1
    return c
сир, чист = з_кодом_в_описі(сирі), з_кодом_в_описі(feed.читати_yml(чистий)[0])
print("РЯДОК 202 — код моделі в голові `param %s` (перші %d слів): у СИРОМУ архіві %d %s, "
      "у ЧИСТОМУ каталозі %d %s" % (ЧК.ПАРАМ_ОПИСУ, ЧК.ГОЛОВА_ОПИСУ, sum(сир.values()),
      dict(сир) or "—", sum(чист.values()), dict(чист) or "—"))
