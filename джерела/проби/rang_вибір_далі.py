# -*- coding: utf-8 -*-
"""П.5: куди вибір їде далі (bridge._пакет:443-495, #108 на живому шляху).
Профіль 1: обрати чипом кольорову й нейтральну основу, порівняти пул слоту
«верх» і тоновий якір спеціфікації схеми до/після вибору."""
import sys, os, json, tempfile
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, feed as Ф

d = json.load(open("стенд_вх.json", encoding="utf-8"))
d["каталог"] = Ф.каталог_на_диску("каталог_brief.xml")
кеш = os.path.join(tempfile.gettempdir(), "кеш_вибір_далі.json")
if not os.path.exists(кеш): json.dump({}, open(кеш, "w"))
d["кеш_кольорів"] = кеш

F, T, зріст, kw = B._збірка(d)
якір, намір = B._якір(d), d.get("намір") or "conventional"
о = B._основи(F, intent=намір)
ВИБОРИ = {
    "колір": dict(база=о["кольори"][0]["ключ"], база_hex=о["кольори"][0]["hex"], база_тип="колір"),
    "нейтраль": dict(база=о["нейтралі"][0]["ключ"], база_hex=о["нейтралі"][0]["hex"], база_тип="нейтраль"),
}

пули = {}
for назва, вибір in ВИБОРИ.items():
    п = B._пакет(F, T, зріст, kw, якір, намір, d.get("самозвіт"), вибір, d.get("драп"))
    спец = п["палітри"]["розвилка"][0]["спец"]
    вх = dict(d, вибір_кольору=вибір)
    з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    kand = (з.get("кандидати") or {}).get("верх") or []
    пули[назва] = {r["id"] for r in kand}
    print("вибір «%s» база=%s: якір_тон=%s (%s), пул «верх»=%d"
          % (назва, вибір["база_hex"], спец["якір_тон"], спец["якір_джерело"], len(kand)))

а, б = пули["колір"], пули["нейтраль"]
print("перетин id пулу «верх»: %d/%d (колір ∩ нейтраль)" % (len(а & б), min(len(а), len(б)) or 1))
