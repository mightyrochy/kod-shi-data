# -*- coding: utf-8 -*-
"""K-OUT-45 (замша під сіллю: домашнє чищення ЗАБОРОНЕНО) — БЕЗ ВХОДУ в каталозі.

ВИМІРЯНО (каталог_повний.xml, слот «верхній_шар», 618 речей): склад оголошено на
501, мовчить на 117; натуральної замші чи нубуку — НУЛЬ. Дві речі з ЕКОЗАМШІ
правило свідомо не бере (синтетика тримає сіль краще за натуральну замшу).
ПОЛАГОДЖЕНО ПОРУЧ: сльота більше не потребує прапорця `реагенти`, а мовчання по
солі розведено надвоє — «склад стійкий» проти «складу не оголошено».
ЧЕСНО ВИМКНЕНО: емітент живий (доводить це нижче), входу в каталозі нема."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, outer as OU

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
вх["сценарій"].update(темп_c=-2, опади="мокрий_сніг")
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
вш = [c for c in кат.values() if c.get("слот") == "верхній_шар"]
замша = [c for c in вш if OU._основи(c, ("замш", "нубук"))]
екозамша = [c for c in вш if "екозамш" in " ".join(
    str(c.get(k) or "").lower() for k in ("матеріал", "матеріал_верху", "назва"))]
print("верхніх речей %d · зі складом %d · натуральна замша/нубук %d · екозамша %d"
      % (len(вш), sum(1 for c in вш if c.get("матеріал")), len(замша), len(екозамша)))
print("приклади екозамші:", [c["назва"][:38] for c in екозамша[:2]])
# емітент на оголошеному складі «замша» — та сама функція, той самий сценарій
замшева = dict(вш[0], слот="верхній_шар", назва="Тренч замшевий", матеріал="замша")
зн = OU.догляд([замшева], темп_c=-2, опади="мокрий_сніг")
for z in зн:
    print("на оголошеній замші: %s %s %.2f · %s"
          % (z["правило"], z["сила"], z["сила_нп"], z["суть"][:52]))
# а те, що каталог справді дає: склад не оголошено → ПИТАННЯ, не мовчання
без_складу = next((c for c in вш if not c.get("матеріал")), None)
пит = OU.догляд([dict(без_складу, слот="верхній_шар")], темп_c=-2, опади="мокрий_сніг")
print("річ без оголошеного складу →",
      [(z["правило"], z["сила"]) for z in пит] or "мовчання")
