"""Сходи ремонту повноти: спроба 1 → адресна спроба 2 → добір кодом (власник, 19.09).

ДО ПРАВКИ ремонт мав ПРАВО не завершитись: одна спроба моделі, і якщо вона не
доповнила — на картку йшов неповний образ із чесним рядком. ПІСЛЯ: чесний рядок
лишається ЛИШЕ там, де в пулі кандидата нема (випадок «г»)."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import pipeline as PL, реєстр_правил as Р

СЦ = {"нагода": "побачення"}
річ = lambda і, с, н: dict(id=і, слот=с, назва=н, тип=н)
ПУЛ = {"сукня": [річ("d1", "сукня", "Сукня міді")], "взуття": [річ("s1", "взуття", "Човники")],
       "сумка": [річ("b1", "сумка", "Клатч"), річ("b2", "сумка", "Шопер")],
       "пояс": [річ("p1", "пояс", "Пасок")]}
БЕЗ_СУМОК = {с: р for с, р in ПУЛ.items() if с != "сумка"}


def вердикт(ід, пул):
    речі = [dict(next(r for п in пул.values() for r in п if r["id"] == і)) for і in ід]
    бл = PL.блокери_структури(PL.структура_образу(речі, None, СЦ), речі)
    return {"образи": [{"ід": "о1", "речі": list(ід), "структура": {"ок": not бл, "блокери": бл}}]}


def сходи(модель, пул, ід):
    """Той самий порядок, що в показі: поки Python дає промпт — спроба; далі добір."""
    викликів = 0
    for спроба in range(1, Р.C["спроб_повноти"] + 1):
        if PL.повнота_набору(вердикт(ід, пул), кандидати=пул, сценарій=СЦ)["повний"]:
            break
        викликів += 1
        ід = модель(спроба, ід)
    return викликів, PL.повнота_набору(вердикт(ід, пул), кандидати=пул, сценарій=СЦ, дібрати=True)


for назва, пул, модель in (
        ("а) доповнює з першого разу", ПУЛ, lambda с, ід: ід + ["b1", "p1"]),
        ("б) доповнює з другого", ПУЛ, lambda с, ід: ід + (["b1"] if с == 1 else ["p1"])),
        ("в) не доповнює ніколи", ПУЛ, lambda с, ід: ід),
        ("г) пул без сумок", БЕЗ_СУМОК, lambda с, ід: ід)):
    в, п = сходи(модель, пул, ["d1", "s1"])
    print("%-28s викликів %d · на картку %s · додав_код %s · жінка бачить: %s"
          % (назва, в, п["ід"], [d["слот"] for d in п["дібрані"]] or "—",
             п["рядок_добору"] or п["рядок"] or "нічого зайвого"))
