# -*- coding: utf-8 -*-
"""Перевіряє місце зібраної речі в суді палітри й три стани входу сегментації."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import суд_образу as суд
import pipeline
import місце_речі as місце
from вхід_правила import нема_входу


def main():
    """Друкує результат читачів для відомого, невідомого й непевного місця."""
    вади = 0
    риса = dict(волосся=dict(L=30.0, a=0.0, b=0.0))
    for слот, слова, вимір, очікуваний in (("верх", None, None, None), ("верх", "так", None, True),
            ("верх", "ні", None, False), ("верх", None, 0.9, None), ("сережки", None, 0.9, True), ("взуття", None, None, False)):
        річ = dict(id="верх", слот=слот, lab=[30.0, 0.0, 0.0], near=вимір)
        зібрана = dict(річ, місце_стилістки=dict(біля_обличчя=слова))
        форми = (зібрана, dict(зібрана, місце_речі=місце.записати(зібрана)))
        for форма in форми:
            точка = pipeline._кольори_образу([форма], {"верх": річ})[0]
            бік = місце.бік_межі(точка[-1])
            елемент = dict(річ="верх", слот="верх", lab=річ["lab"],
                           місце_речі=місце.записати(форма))
            if "місце_речі" in форма:
                елемент["місце_речі"] = форма["місце_речі"]
            знахідки = суд.перевірка_сегментації(риса, [елемент])
            висновки = [з for з in знахідки if not нема_входу(з)]
            без_входу = [з for з in знахідки if нема_входу(з)]
            print(слот, слова, вимір, "запис" if "місце_речі" in форма else "річ",
                  "бік:", бік, "висновків:", len(висновки), "без входу:", len(без_входу))
            вади += бік is not очікуваний
            вади += len(висновки) != int(очікуваний is True)
            вади += len(без_входу) != int(очікуваний is None)
    print("вад:", вади)
    return bool(вади)


if __name__ == "__main__":
    sys.exit(main())
