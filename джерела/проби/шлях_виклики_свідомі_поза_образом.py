# -*- coding: utf-8 -*-
"""Розбір шляху 4/8 · оголошений хід про річ, якої нема в образі. Відповідь ремонту: о1 без головного убору, а в
його «свідомо» — номер берета з пулу (так gemma на p331 s7_1: «#48·14» при о3 без берета). Друкує: що код записав
в `образ.свідомі` і чи адресат є серед речей образу; що несе вибір «о1»; що стоїть у промпті ОПИС_V1 у «свідомі»
проти «образ.речі» — тим самим входом, який шле показ (`показ.html`, виклик `містП('опис')`).
Запуск: cd джерела && python3 проби/шлях_виклики_свідомі_поза_образом.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), варіантів=10, ремонт_варіантів=5, бюджет_символів=120000, без_фото=1)
пул = json.loads(json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["руки"]["1"])["пул"]
н = lambda с, k: пул[с][k % len(пул[с])]["н"]
убір = пул["головний_убір"][0]
від = lambda т, **д: json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=т, **д), ensure_ascii=False)))
образи = [dict(ід="о%d" % (і + 1), підпис="беж", день="Офіс.", речі=[н(с, і) for с in ("верх", "низ", "взуття", "сумка", "пояс")]) for і in range(5)]
в1 = від(json.dumps(dict(версія="1", образи=образи), ensure_ascii=False))
образи[0]["свідомо"] = [dict(річ=убір["н"], чому="оголошений розрив: ніжний акцент біля обличчя")]
образи[0]["день"] = "Убір додасть свіжості, додано взуття для ходи."
в2 = від(json.dumps(dict(версія="1", образи=образи), ensure_ascii=False), ітерація=2, попередній_вердикт=в1["вердикт"])
о1 = в2["образи"][0]
print("убір у пулі: %s «%s» · у складі о1: %s" % (убір["н"], убір["назва"], убір["н"] in образи[0]["речі"]))
for с in о1.get("свідомі") or []:
    print("образ.свідомі о1: «%s» · ід %s · серед речей о1: %s" % (с.get("текст"), с.get("ід"), с.get("ід") in (о1.get("ід") or [])))
в3 = від(json.dumps(dict(версія="1", обрано="о1", чому="так", прибрати=[])), ітерація=2, відповідь="ВИБІР_V1", вибір_над=в2["вибір_над"])
вб = в3.get("вибір") or {}
print("вибір: ід %d · день «%s» · верхній рівень свідомі %s" % (len(вб.get("ід") or []), вб.get("день"), [x.get("текст") for x in в3.get("свідомі") or []]))
о = json.loads(B.виклик("опис", json.dumps(dict(вх, речі=вб.get("ід"), підпис=вб.get("підпис"), номери=вб.get("номери"), образ=вб.get("обрано"),
               свідомі=[x.get("текст") for x in в3.get("свідомі") or []], день=вб.get("день") or ""), ensure_ascii=False)))
п = json.loads(о["промпт"])
print("промпт опису: образ.речі %s" % [r.get("назва")[:30] for r in п["образ"]["речі"]])
print("   свідомі %s · день_образу «%s»" % (п.get("свідомі"), п.get("день_образу")))
print("   убір в образ.речі: %s · убір у свідомі: %s" % (any(убір["назва"][:20] in r.get("назва", "") for r in п["образ"]["речі"]),
                                                      any(убір["назва"][:20] in s for s in п.get("свідомі") or [])))
