"""ЗОНА ВІД МОДЕЛІ (рядок 188). Рядок 156 загейтив типи, тканини й принти її словами, а зони лишив
із причиною «їх ставить рукою сама жінка». Файл вердиктів тестувальниці «Ір» (23.09 09:16) показав,
що ставить їх і МОДЕЛЬ: прогони 2–5 «для авто та на урок, надворі дощ…» → `вето.зони=["ноги"]` при
`вето_зони=null` і без згадки ніг у її словах; прогін 1, концерт → ["живіт","спина"]. Зона «ноги»
знімає з пулу міні, шорти й короткі спідниці, а в рядку випадку стоїть «Не хоче: … ноги» — у всіх
чотирьох промптах. Проба рахує зони БЕЗ ОПОРИ В СЛОВАХ ДО і ПІСЛЯ; контроль — її власні відмови й
чип. Запуск: cd джерела && python3 проби/zony_vid_modeli_188.py"""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import pipeline as PL
ІР = "для авто та на урок, надворі дощ. Можна яскравий верх — куртку чи жакет, не темного кольору"
КОНЦЕРТ = "Іду на концерт музичний в театрі, вечір, буде прохолодно, для зручної прогулянки кілька км"
ВИПАДКИ = [   # (мітка, слова жінки, зони в паспорті, чипи її рукою, зони, які код МУСИТЬ тримати межею)
    ("Ір, прогони 2–5", ІР, ["ноги"], [], []), ("Ір, прогін 1 — концерт", КОНЦЕРТ, ["живіт", "спина"], [], []),
    ("«не відкриваю ноги»", "сукня по коліно, не відкриваю ноги", ["ноги"], [], ["ноги"]),
    ("«без декольте»", "хочу сукню, без декольте", ["декольте"], [], ["декольте"]),
    ("«закрита спина»", "хай буде закрита спина", ["спина"], [], ["спина"]),
    ("«не оголюю живіт»", "не оголюю живіт, решта як хочеш", ["живіт"], [], ["живіт"]),
    ("«плечі прикриті»", "плечі прикриті, будь ласка", ["плечі"], [], ["плечі"]),
    ("чип рукою, слів нема", ІР, ["живіт"], ["живіт"], ["живіт"]),
    ("чип рукою + зона моделі", ІР, ["живіт", "ноги"], ["живіт"], ["живіт"]),
    ("«без декольте, зате відкриті плечі»", "без декольте, зате відкриті плечі", ["декольте", "плечі"], [], ["декольте"])]
без_опори, згублено, її = [0, 0], [0, 0], [0, 0]      # `її` — лише два випадки з її файла вердиктів
for н, (мітка, слова, зони, чипи, треба) in enumerate(ВИПАДКИ):
    п = dict(слова=слова, зони_чипами=list(чипи),
             вето=dict(типи=[], тканини=[], принти=[], кольори=[], зони=list(зони)))
    for i, є in enumerate([list(зони), PL.вето_тверде(п)["зони"]]):     # ДО (сире) / ПІСЛЯ (гейт)
        без_опори[i] += len([z for z in є if z not in треба]); згублено[i] += len([z for z in треба if z not in є])
        її[i] += len([z for z in є if z not in треба]) if н < 2 else 0
        if i and (set(є) - set(треба) or set(треба) - set(є)):
            print("   ✗ %-42s → зайве %s · бракує %s" % (мітка, sorted(set(є) - set(треба)), sorted(set(треба) - set(є))))
print("випадків %d · зон БЕЗ ОПОРИ в її словах і без чипа: ДО %d → ПІСЛЯ %d (з них у її файлі вердиктів: ДО %d → ПІСЛЯ %d)"
      "\n   справжніх меж — її відмов і чипів — згублено: ДО %d → ПІСЛЯ %d"
      % (len(ВИПАДКИ), без_опори[0], без_опори[1], її[0], її[1], згублено[0], згублено[1]))
print("   місце «У дорозі» з її слів: «%s…» → %s · «лечу літаком 8 годин у дорозі» → %s"
      % (ІР[:18], "коротка поїздка, ключ не беремо" if PL.дорога_коротка(ІР) else "ДОВГА",
         "коротка" if PL.дорога_коротка("лечу літаком, 8 годин у дорозі") else "довга дорога, ключ беремо"))
assert (без_опори[1], згублено[1]) == (0, 0), "зона без опори лишилась або справжню межу згублено"
assert PL.дорога_коротка(ІР) and not PL.дорога_коротка("лечу літаком, 8 годин у дорозі"), "дорога розпізнана хибно"
