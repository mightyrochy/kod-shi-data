"""Справжній міст: відомі інтервали поза обраною основою означають «ні»."""
import json
import runpy
import sys
from unittest.mock import patch
sys.path.insert(0, ".")
import bridge as Б, міст_відповіді as М


def головна():
    """Повторити паспорт 1551, замінивши колір великих речей відомим темним інтервалом."""
    сцена = runpy.run_path("проби/основа_на_великій_1551.py", run_name="__main__")
    ід = сцена["ід"]
    штатний, великих = М._пакет_каталогу, []
    def з_інтервалами(*а, **к):
        """Змінити лише колір у реально отриманому пакеті, незалежно від його кешування."""
        пак = штатний(*а, **к)
        for р in пак.get("_каталог") or []:
            if р.get("id") in ід and р.get("слот") in ("верх", "низ", "сукня", "комплект", "верхній_шар"):
                р.update(колір_тип="інтервал", lab=None, colors=[],
                         колір_не_вимір=dict(свідок="shop_word", вікно=(10, 12, 30, 35, (20, 25))))
                великих.append(р["id"])
        return пак
    with patch.object(М, "_пакет_каталогу", side_effect=з_інтервалами):
        вих = json.loads(Б.виклик("від_моделі", json.dumps(dict(сцена["вх"], ід=ід), ensure_ascii=False)))
    assert великих
    основа = (вих.get("схема_жінці") or {}).get("основа") or {}
    print("Інтервалів на великих речах:", len(великих), "основа на великій:", основа.get("на_великій"))
    assert основа.get("на_великій") == "ні"


if __name__ == "__main__":
    головна()
