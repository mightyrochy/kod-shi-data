/* Проба журналу P3: однаковий корпус для джерел ДО і ПІСЛЯ, без DOM і мережі.
   Запуск із джерела: node проби/журнал_розбір_1419.js [шлях-ДО/показ.html]
   Друкує факти про великі JSON, тотожність розгорнутих записів і ізоляцію змін.
   Час цієї проби не замінює профіль Chromium після збору. */
const fs = require('fs'), path = require('path'), assert = require('assert/strict');
const після = fs.readFileSync(path.join(__dirname, '..', 'показ.html'), 'utf8');
const до = process.argv[2] ? fs.readFileSync(process.argv[2], 'utf8') : null;
function читач(джерело){
  let великих = 0, великихТекстів = 0;
  const парсер = Object.create(JSON);
  парсер.parse = т => { if (typeof т === 'string' && т.length >= 1000000) великих++; return JSON.parse(т); };
  парсер.stringify = (...а) => { const т = JSON.stringify(...а); if (т && т.length >= 1000000) великихТекстів++; return т; };
  const поч = джерело.indexOf("const ЗВІТ_ФОРМАТ =");
  const кін = джерело.indexOf("/* ── ОДИН ВЕРДИКТ — ОДИН РЯДОК ФАЙЛА", поч);
  assert(поч >= 0 && кін > поч, 'межі читача звіту');
  return Object.assign(new Function('JSON',
    "const пристрій = 'проба'; const ШАПКА = [];\n" + джерело.slice(поч, кін)
    + "\nreturn {розібратиПоле, звітВердиктів, злитиВердикт};")(парсер), {великих: () => великих, великихТекстів: () => великихТекстів});
}
const коли = new Date('2026-10-18T00:00:00Z');
const етапи = [1500000, 2200000].map((н, і) => JSON.stringify({
  прогін: {код: 'пр-' + і}, розмова: {виклики: []}, діагноз_прогону: ['код'],
  виклики: [{текст: 'а'.repeat(н), сире: '{помилковий JSON}', нуль: 0, ні: false}],
  суд: {знахідки: [{правило: 'K-COL-01', сила_нп: 0}]}}));
const записи = () => етапи.map((т, і) => ({прогін: 'пр-' + і, рука: і + 1,
  паспорт: '{"мета":"звично"}', чат: '[{"текст":"а\\nб"}]', етапи: т,
  нуль: 0, ні: false, порожнє: '', невідоме: {код: 'x'}}));
const розгорнути = (ч, звіт) => звіт.прогони.flatMap(п => п.вердикти.map(в => ч.злитиВердикт(звіт, п, в)));
function корпус(ч){
  let перший;
  for (let і = 0; і < 16; і++){
    const сирі = записи(), було = JSON.stringify(сирі);
    const звіт = ч.звітВердиктів(сирі, коли), повні = розгорнути(ч, звіт);
    assert.equal(JSON.stringify(сирі), було, 'сирий журнал незмінний');
    if (перший) assert.deepEqual(повні, перший, 'повторне складання тотожне');
    else перший = повні;
  }
  return перший;
}
const старий = до ? читач(до) : null;
const базовий = старий ? корпус(старий) : null;
if (старий) assert.equal(старий.великих(), 32);
{
  const ч = читач(після), факт = корпус(ч);
  assert.equal(ч.великих(), 2, 'два різні великі етапи розбираються раз');
  if (базовий) assert.deepEqual(факт, базовий, 'розгорнутий звіт ДО = ПІСЛЯ');
  const з = ч.звітВердиктів(записи(), коли);
  розгорнути(ч, з)[0].етапи.виклики[0].текст = 'змінено читачем';
  assert.deepEqual(розгорнути(ч, ч.звітВердиктів(записи(), коли)), факт, 'читач не псує кеш');
  const нові = записи(); нові[0].етапи = '{"суд":{"код":"новий"}}';
  assert.equal(розгорнути(ч, ч.звітВердиктів(нові, коли))[0].етапи.суд.код, 'новий', 'оновлений JSON');
  assert.deepEqual(розгорнути(ч, ч.звітВердиктів(записи(), коли)), факт, 'повернення до попереднього значення');
  for (const т of ['', '{', 'null', 'false', '0', '"рядок"']) assert.equal(ч.розібратиПоле(т), т);
  assert.deepEqual(ч.розібратиПоле('[]'), []); assert.deepEqual(ч.розібратиПоле('{}'), {});
  const небезпечне = ч.розібратиПоле('{"__proto__":{"код":"дані"},"a":[null,false,0]}');
  assert(Object.hasOwn(небезпечне, '__proto__')); assert.equal(небезпечне.__proto__.код, 'дані');
  const протоЗвіт = ч.звітВердиктів([{прогін:'прото', етапи:'{"__proto__":{"код":"дані"},"суд":{"код":"рука"}}'}], коли);
  const протоЕтапи = протоЗвіт.прогони[0].вердикти[0].етапи;
  assert(Object.hasOwn(протоЕтапи, '__proto__'), 'report зберігає власне поле __proto__');
  assert.equal(протоЕтапи.__proto__.код, 'дані');
  assert.equal(JSON.parse(JSON.stringify(протоЗвіт)).прогони[0].вердикти[0].етапи.__proto__.код, 'дані');
  const протоРозгорнуто = ч.злитиВердикт(протоЗвіт, протоЗвіт.прогони[0], протоЗвіт.прогони[0].вердикти[0]);
  assert(Object.hasOwn(протоРозгорнуто.етапи, '__proto__'), 'декодер теж зберігає власне поле __proto__');
  const об = [{прогін:'об', етапи:{прогін:{код:'свій'}, розмова:{}, суд:{код:'рука'}}}];
  const було = JSON.stringify(об); ч.звітВердиктів(об, коли);
  assert.equal(JSON.stringify(об), було, 'об’єктні етапи не втрачають спільного');
  const спільніЗаписи = () => [1,2].map(рука => ({прогін:'спільний', рука,
    етапи:JSON.stringify({прогін:{текст:'ж'.repeat(1100000)}, суд:{рука}})}));
  const спільні = спільніЗаписи(), першийСпільний = ч.звітВердиктів(спільні, коли);
  if (старий) assert.deepEqual(першийСпільний, старий.звітВердиктів(спільні, коли), 'спільні етапи ДО = ПІСЛЯ');
  const текстів = ч.великихТекстів();
  першийСпільний.прогони[0].спільне.етапи.прогін.текст = 'читач змінив копію';
  for (let і=0; і<8; і++) assert.equal(ч.звітВердиктів(спільніЗаписи(), коли).прогони[0].спільне.етапи.прогін.текст.length, 1100000);
  assert.equal(ч.великихТекстів(), текстів, 'спільне поле незмінного розбору не серіалізується повторно');
  const зміненіОб = спільніЗаписи().map(з => ({...з, етапи:ч.розібратиПоле(з.етапи)}));
  зміненіОб[1].етапи.прогін.текст = 'змінено до складання';
  assert(!ч.звітВердиктів(зміненіОб, коли).прогони[0].спільне.етапи, 'об’єктний вхід порівнює поточні поля');
  const іншіСпільні = спільніЗаписи();
  іншіСпільні[1].етапи = JSON.stringify({прогін:{текст:'новий'}, суд:{рука:2}});
  assert(!ч.звітВердиктів(іншіСпільні, коли).прогони[0].спільне.етапи, 'новий JSON не використовує старе порівняння');
  const глибокий = '['.repeat(12000) + '0' + ']'.repeat(12000);
  let вкладений = ч.розібратиПоле(глибокий);
  for (let і = 0; і < 12000; і++) вкладений = вкладений[0];
  assert.equal(вкладений, 0, 'глибокий JSON без рекурсії копіювання');
  const давній = '{"суд":{"код":"давній"}}';
  ч.розібратиПоле(давній);
  for (let і = 0; і < 20; і++) ч.розібратиПоле(JSON.stringify({код: і}));
  assert.equal(ч.розібратиПоле(давній).суд.код, 'давній', 'витіснений запис читається знову');
  const завеликий = JSON.stringify({текст:'x'.repeat(9 * 1024 * 1024)});
  assert.equal(ч.розібратиПоле(завеликий).текст.length, 9 * 1024 * 1024, 'запис поза кешем не обрізається');
  console.log('Великі розбори 32 → 2; повтори, зміни, помилки, об’єктні етапи, витіснення — без втрати');
}
if (старий) { console.log('ДО → ПІСЛЯ: розгорнутий звіт тотожний'); }
else console.log('ДО не задано: порівняння з базою не виконано');
