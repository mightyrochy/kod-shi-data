# -*- coding: utf-8 -*-
"""Рядок 1972: ремонт гейтів (`_ремонт_гейтів`) і її закріплена річ з фото. Пул — стенд (`стенд_вх.json`, офіс), сіди 3, 5, 7;
її річ «її-ф1» (`власна`, `закріплена`) — пальто чи верх. Гейти: K-OUT-06 [светр, її пальто] (її річ — верхній шар), K-PAL-03
лише на її речі (номером, повз `без_замків`), гейт без адрес (запас — увесь склад). Суддя-заглушка приймає БУДЬ-ЯКИЙ варіант:
так видно, що ремонт узагалі пропонує. Факт — варіанти без її речі й узяті варіанти без її речі (ДО — на базі пачки 2)."""
import json, sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, повнота_образу as ПО
суддя = lambda набори: [dict(структура=dict(ок=True, блокери=[]), знахідки=[]) for _ in набори]
варіантів = без_неї = взято_без_неї = ремонтів = 0
for сід in (3, 5, 7):
    вх = dict(json.load(open("стенд_вх.json")), сід=сід)
    к = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["кандидати"]
    for слот, гейт in (("верхній_шар", "K-OUT-06"), ("верх", "K-PAL-03"), ("верх", "K-COL-01")):
        її = dict(id="її-ф1", слот=слот, власна=True, закріплена=True, назва="її річ")
        інші = [к[с][сід % len(к[с])]["id"] for с in ("верх", "низ", "взуття", "сумка") if с != слот or слот == "верхній_шар"]
        ід = [її["id"]] + інші
        словник = dict({r["id"]: dict(r, слот=с) for с, пул in к.items() for r in пул}, **{її["id"]: її})
        речі = {"K-OUT-06": [інші[0], її["id"]], "K-PAL-03": ["її річ"], "K-COL-01": []}[гейт]
        образ = dict(знахідки=[dict(правило=гейт, регістр="гейт", речі=речі)], структура=dict(ок=True, блокери=[]))
        бачено = []
        _суд = lambda н: (бачено.extend(н), суддя(н))[1]
        ід2, зміна, звіт = ПО._ремонт_гейтів(ід, {}, образ, dict(к), словник, {}, _суд)
        ремонтів += 1
        варіантів += len(бачено); без_неї += sum(1 for в in бачено if її["id"] not in в)
        взято_без_неї += bool(ід2) and її["id"] not in ід2
        if сід == 3: print("   %-9s її річ у слоті %-11s → варіантів %d, без її речі %d · взято: %s"
                           % (гейт, слот, len(бачено), sum(1 for в in бачено if її["id"] not in в), (звіт or {}).get("взято")))
print("ремонтів %d · варіантів %d, з них без її закріпленої речі %d · узятих варіантів без її речі %d"
      % (ремонтів, варіантів, без_неї, взято_без_неї))
