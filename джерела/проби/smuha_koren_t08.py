# -*- coding: utf-8 -*-
"""Т-08: чи тримається її відмова, сказана ЇЇ формою слова.

Вето моделі канонічне («смужка»), а жінка каже «СМУГАстий». Основа «смуж» у
«смугастий» не стоїть, тож гейт рядка 156 нічого не підтверджував і знімав її
власну відмову разом із вето моделі. Факт — на шести фразах і на каталозі.
Запуск із теки `джерела`: PYTHONPATH=. python3 проби/smuha_koren_t08.py"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, feed as Ф
СЦ = dict(нагода="робота", місце="офіс_креативний", година=11, темп_c=18)
ВХ = json.load(open("стенд_вх.json", encoding="utf-8"))
ВХ["каталог"] = Ф.каталог_на_диску("каталог_brief.xml")


def межа(слова):
    """`жорстке_ні` для вето «смужка» плюс цих слів жінки (порожнє — межі нема)."""
    д = B._застосувати_паспорт(dict(сценарій=dict(СЦ), паспорт=dict(
        вето=dict(принти=["смужка"], типи=[]), слова=слова)))
    return д["жорстке_ні"] or []


def смугастих(слова):
    """Скільки смугастих речей лишилось у кандидатах при цих словах жінки."""
    п = dict(вето=dict(принти=["смужка"]), слова=слова)
    r = json.loads(B.виклик("запити", json.dumps(dict(ВХ, паспорт=п), ensure_ascii=False)))
    р = [x for с in r["кандидати"].values() for x in с]
    return sum(1 for x in р if re.search(r"полос|смуг|смуж", str(x.get("назва") or ""), re.I)), len(р)


for ф in ("не хочу смужку", "у смужку не ношу ніколи", "смугастий одяг мені не йде",
          "смугастий одяг не ношу", "в полоску не ношу", "люблю смужку"):
    print("%-34s → межа %s" % ("«%s»" % ф, межа(ф) or "НЕМА"))
assert межа("смугастий одяг мені не йде"), "її корінь не тримається межею"
assert not межа("люблю смужку"), "похвала стала межею (регресія рядка 156)"
for ф in ("", "не хочу смужку", "смугастий одяг мені не йде"):
    print("каталог · слова «%s» → смугастих %d із %d" % (ф or "—", *смугастих(ф)))
assert смугастих("смугастий одяг мені не йде")[0] == 0
