"""Рядки 3370, 3312: обгортка {"answer": {…}} над відповіддю без схеми (`протокол.розбір_останній`).

ДО: знімав її лише `розбір_за_схемою`; записані відповіді шару фото ЖИВІ-12 Б/01–03 — 1/5 розібрано
(4 — «відповідь без списку items», повтор і друге, інше прочитання того самого фото).
ПІСЛЯ: 5/5 з назвою й слотом; той самий розбір у РЕЧІ оцінки, переліку рук 3–4 і виборі палітри;
поле «answer» мосту й допиту — як доти."""
import sys, pathlib, json, glob
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import річ_з_фото as РФ, оцінка_образу as ОО, руки_без_коду as РБК, міст_стилістка as МС, протокол as ПР

ф1 = [{"ід": "ф1", "ширина": 1000, "висота": 1000}]
добрі = 0
шляхи = sorted(glob.glob(str(_К.parent / "аудит/живі_12/Б/0[1-3]*/VIDPOVIDI/*речі_з_фото*")))
for ш in шляхи:
    відп = open(ш, encoding="utf-8").read().split("── ВІДПОВІДЬ", 1)[1].split("\n", 1)[1]
    в = РФ.речі_з_відповіді_фото(відп, ф1)
    р = [(х.get("назва"), х.get("слот")) for х in в["речі_з_фото"]]
    добрі += bool(в["причина"] is None and р and all(н and с for н, с in р))
    print(pathlib.Path(ш).parent.parent.name[:2], pathlib.Path(ш).name[:8], "причина:", в["причина"],
          "речі:", р, "нотатки:", в.get("нотатки"))
print("шар фото Б/01–03: розібрано з назвою й слотом %d/%d" % (добрі, len(шляхи)))

річ = {"photo": "ф1", "name": "sandal", "slot": "shoes", "color": "white", "pattern": "solid", "owner": "mine"}
з_обг = json.dumps({"answer": {"items": [річ]}})
print("оцінка РЕЧІ:", len(ОО.речі_з_відповіді(з_обг, ф1)["речі"]), "речей,",
      ОО.речі_з_відповіді(з_обг, ф1)["нотатки"])
print("перелік рук 3–4:", len(РБК.речі_переліку(з_обг) or []), "речей")
print("вибір палітри (scheme):", ПР.розбір_останній('{"answer": {"scheme": "triad"}}', ("scheme",))[0])
print("міст (поле answer) як доти:", МС.прийняти('{"answer": "так"}'),
      "| мовний шар (поля ()) як доти:", ПР.розбір_останній('{"answer": {"a": 1}}', ())[0])
