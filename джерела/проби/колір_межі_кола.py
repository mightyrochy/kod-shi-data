# -*- coding: utf-8 -*-
"""КОЛІР-КОДУВАННЯ (рядок 2693), п.3: художні межі відповідностей — за колом художника (`колір_простір_риси._КОЛО`,
K-COL-03 §4). (а) Скільки розбиттів кола тону тримає код і куди кожне кладе лайм і смарагд (тони якорів —
коментар над `колір_річ.FAMILIES`). (б) Дуга відлуння `ДУГА_ВІДЛУННЯ` = 45° CIELAB у градусах кола художника
по ділянках: одне число CIELAB — різна художня відстань. (в) Пари: Δ на колі художника → клас за межами корпусу
(відлуння / в тон ≤15°, сусідні 15–45°, аналогові до 75°, тріада 120±25, розщеплена 150±22, комплемент
180±30 — `RELATIONS` і `палітра_схеми`), і що каже нинішнє відлуння CIELAB 45° на ВИМІРІ та на словах.
Запуск із джерела/: python3 проби/колір_межі_кола.py"""
import sys; sys.path.insert(0, ".")
import колір_простір_риси as КП, колір_річ as КР, palettes as PS, verify as V
ДУГА_ВІДЛУННЯ = 45.0   # дуга відлуння ДО КОЛІР-Р2 (CIELAB); нині — `колір_річ.ДУГА_ВІДЛУННЯ` на колі художника
ЯК = dict(лайм=119.7, смарагд=151.6, хвоя=156.3, бірюза=185.2, червоний=40.0, помаранч=59.6, гірчиця=87.4,
          жовтий=102.9, блакить=235.1, кобальт=291.1, бордо=25.0, мідь=54.0, кемел=69.0, нейві=282.0)
кх = КП.у_коло_художника
д = lambda a, b: abs((a - b + 180) % 360 - 180)
def клас(дх):
    for межа, ім in ((15, "відлуння / в тон"), (45, "сусідні (крок кола)"), (75, "аналогові"), (95, "—"),
                     (145, "тріада"), (150, "тріада/розщеплена"), (172, "розщеплена"), (181, "комплемент")):
        if дх <= межа: return ім
def на(h, дуги): return [ім for lo, hi, ім in дуги if (lo <= h < hi if lo < hi else (h >= lo or h < hi))]
сімї = [(lo, hi, ім) for ім, рр in PS.СІМ_Ї.items() for rr in рр.values() if rr for lo, hi in [rr]]
слова = [(в[4][0], в[4][1], с) for с, в in V.ЛЕКСИКОН.items() if в[4] and в[3] > 15]
print("(а) розбиття кола тону в коді:")
for ім, h in (("лайм", ЯК["лайм"]), ("смарагд", ЯК["смарагд"])):
    print("  %-8s CIELAB %5.1f° · коло художника %5.1f° · FAMILIES %s · palettes.СІМ_Ї %s · вікна слів %s"
          % (ім, h, кх(h), на(h, [(lo, hi, n) for lo, hi, n in КР.FAMILIES]), на(h, сімї), на(h, слова)))
print("(б) %d° CIELAB = скільки градусів кола художника (крок 12-кольорового кола — 30°):" % ДУГА_ВІДЛУННЯ)
for h in (10, 40, 70, 100, 130, 160, 190, 220, 250, 280, 310, 340):
    print("  від %3d°: %5.1f°" % (h, д(кх(h + ДУГА_ВІДЛУННЯ), кх(h))), end="\n" if h in (100, 220, 340) else "")
print("(в) пари: Δ CIELAB · Δ коло художника → клас за колом · відлуння CIELAB 45° (вимір) · на словах «зелений»×«зелений»")
for a, b in (("лайм", "смарагд"), ("смарагд", "хвоя"), ("червоний", "помаранч"), ("бордо", "мідь"),
             ("блакить", "кобальт"), ("гірчиця", "лайм"), ("бордо", "хвоя"), ("кемел", "нейві"), ("бірюза", "мідь")):
    дц, дх = д(ЯК[a], ЯК[b]), д(кх(ЯК[a]), кх(ЯК[b]))
    print("  %-9s × %-9s %5.1f° · %5.1f° → %-20s · %s" % (a, b, дц, дх, клас(дх), "так" if дц <= ДУГА_ВІДЛУННЯ else "ні"))
x = dict(колір_не_вимір=dict(вікно=V.ЛЕКСИКОН["зелений"]))
print("  «зелений» × «зелений» (вікно 100–180° CIELAB):", КР.поруч_за_тоном(x, x, ДУГА_ВІДЛУННЯ),
      "· розкид Δ тону", КР.розкид_тону(x, x))
