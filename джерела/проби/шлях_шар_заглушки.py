"""М-2, вада 3: ЗАГЛУШКИ В ПРОМПТАХ МОВНОГО ШАРУ І ТЕ, ЩО З НИХ ДОХОДИТЬ. (1) Скільки рядків-
заглушок (`<…>`, «…») стоїть у кожному промпті шару: перекладач сценарію, коментаря до образу,
текстів і репліки. (2) На всіх збережених відповідях перекладача сценарію з живого прогону 26.09
(`аудит/тести/сирі_2026-09-26/*.tar.gz`): скільки заглушок повернула модель, скільки з них стало
внутрішньою мовою (`прийняти_вхід`) і скільки — паспортом (`паспорт_з_шару`), і скільки полів
відкинув сторож (кількість та сама — сторож не слабшає). Та сама проба на main і на гілці.
Запуск із `джерела`: python3 проби/шлях_шар_заглушки.py"""
import sys, os, re, glob, tarfile, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import мовний_шар as МШ

ЗАГЛ = re.compile(r"<[^<>\n]{1,80}>|…")
промпти = {"сценарій": МШ.промпт_входу("scenario", "слова"),
           "коментар": МШ.промпт_входу("verdict_comment", "слова", {"items": []}),
           "тексти": МШ.промпт(МШ.розмітити({"опис": "Тримайте сумку в руці."})),
           "репліка": МШ.промпт_репліки({"recorded": {"occasion": "date"}, "advice_topics": ["makeup"]})}
for ім, п in промпти.items():
    print("промпт «%s»: символів %d · заглушок %d %s" % (ім, len(п), len(ЗАГЛ.findall(п)),
                                                      sorted(set(ЗАГЛ.findall(п)))[:4]))
у_відп = у_вн = у_паспорті = відкинуто = відповідей = 0
for тар in sorted(glob.glob("../аудит/тести/сирі_2026-09-26/*.tar.gz")):
    with tarfile.open(тар) as т:
        for ч in т.getmembers():
            с = т.extractfile(ч).read().decode("utf-8").replace("\r\n", "\n") if ч.isfile() else ""
            if "слова жінки про її вихід" not in с or "── ВІДПОВІДЬ" not in с:
                continue
            слова = re.split(r"\n\n(?:КОНТЕКСТ:|── ВІДПОВІДЬ)", с.split("\nСЛОВА:\n", 1)[1])[0].strip()
            сире = с.split("── ВІДПОВІДЬ", 1)[1].split("──\n", 1)[1]
            вн = МШ.прийняти_вхід("scenario", сире)["внутрішня"]
            р = МШ.паспорт_з_шару(вн, {}, None, None, слова_ходу=слова)
            відповідей += 1
            у_відп += len(re.findall(r'"<[^"<>]*>"', сире))
            у_вн += len(re.findall(r'"<[^"<>]*>"', json.dumps(вн, ensure_ascii=False)))
            у_паспорті += len(re.findall(r'"<[^"<>]*>"', json.dumps(р["паспорт"], ensure_ascii=False, default=str)))
            відкинуто += len(р["вигадки"])
print("збережених відповідей %d: заглушок у відповідях моделі %d · у внутрішній мові %d · у паспорті %d · "
      "сторож відкинув полів %d" % (відповідей, у_відп, у_вн, у_паспорті, відкинуто))
