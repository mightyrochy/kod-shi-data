"""Рядок 5500: скільки людських пар «рука 1 ↔ рука 2» треба на ОДНЕ правило, щоб скарга на зламаний аспект у руці 2 проти тієї
самої скарги в руці 1 (база) дала висновок. Тест — точний знаковий на розбіжних парах (скарга лише в руці 2 проти лише в руці 1),
однобічний α=2,5 % (як пороги `рука2_пари.py`); потужність 80 % — точно, через біноміальні розподіли, без симуляції. Скарги в
руках пари вважаються незалежними (обережно: позитивний зв'язок зменшує розбіжні пари й потрібне n). Далі — скільки ТЕСТІВ
(прогонів, де оцінено обидві картки) це коштує при M правилах у черзі, k поломках на тест і частці прогонів, де правило діє.
Запуск: python3 джерела/проби/рука2_скільки_пар.py"""
from functools import lru_cache
from math import comb, sqrt
def хвіст(n, k): return sum(comb(n, i) for i in range(k, n + 1)) / 2.0 ** n
@lru_cache(None)
def поріг(D): return next((k for k in range(D + 1) if хвіст(D, k) <= 0.025), None)   # мінімум «лише рука 2» з D розбіжних
def потужність(n, p1, p2):
    p10, p01 = p2 * (1 - p1), p1 * (1 - p2); pd = p10 + p01; q = p10 / pd; вих = 0.0
    for D in range(n + 1):
        k = поріг(D)
        if k is None: continue
        pD = comb(n, D) * pd ** D * (1 - pd) ** (n - D)
        вих += pD * sum(comb(D, i) * q ** i * (1 - q) ** (D - i) for i in range(k, D + 1))
    return вих
def треба(p1, p2):   # від нормального наближення (McNemar) униз, далі точно вгору
    p10, p01 = p2 * (1 - p1), p1 * (1 - p2); d, pd = p10 - p01, p10 + p01
    n = max(5, int((1.96 * sqrt(pd) + 0.84 * sqrt(pd - d * d)) ** 2 / d ** 2 * 0.8))
    while потужність(n, p1, p2) < 0.8: n += 1
    return n
def вілсон(x, n, z=1.96):
    if not n: return (0.0, 1.0)
    p = x / n; ц = (p + z * z / (2 * n)) / (1 + z * z / n); р = z * sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return (max(0.0, ц - р), min(1.0, ц + р))
print("база (рука 1) → рука 2 · пар на правило для 80 %")
СЦ = [(0.05, 0.35), (0.10, 0.40), (0.10, 0.30), (0.20, 0.40), (0.10, 0.20), (0.05, 0.15)]
нн = {}
for p1, p2 in СЦ:
    нн[(p1, p2)] = треба(p1, p2); print("  %2.0f%% → %2.0f%% · пар %d" % (100 * p1, 100 * p2, нн[(p1, p2)]))
n = нн[(0.10, 0.30)]
print("тестів на ОДНЕ правило при %d парах (сценарій 10%%→30%%), частка прогонів, де правило діє, 0,7:" % n)
for M, k in ((14, 1), (8, 1), (4, 1), (4, 2), (4, 3)):
    print("  правил у черзі %2d · поломок на тест %d · тестів %4.0f (за них кожне правило черги набирає свої %d пар)" % (M, k, n * M / (k * 0.7), n))
for x, m in ((0, 1), (0, 10), (3, 30)):   # межі частки скарг: 1 пара без скарги (як наявна людська K-KOH-02), 10, 30
    print("скарг %d з %d пар: межі Вілсона 95%%: %.0f–%.0f%%" % ((x, m) + tuple(100 * в for в in вілсон(x, m))))
