"""Компаньйон з інтервалом зберігається учасником опори K-PAL-16."""
import sys
from unittest.mock import patch
sys.path.insert(0, ".")
import композитор_оцінка as О


def головна():
    """Перевірити справжній розрахунок контексту та склад опори в оцінці."""
    р = dict(id="межова", слот="верх", колір_тип="інтервал", lab=None, _частка_вікна=.1,
             колір_не_вимір=dict(свідок="shop_word", вікно=(60, 62, 20, 25, (85, 95))))
    комп = dict(р, id="компаньйон", слот="низ", _частка_вікна=1)
    with patch.object(О._PL, "осі", return_value=dict(позиція=dict(hue=1))), \
         patch.object(О._ПЕР, "перевірити_образ", return_value={}):
        знахідки = О.оцінити({}, [р, комп], {}, [], [])[2]
    опора = next(з for з in знахідки if з.get("правило") == "K-PAL-16")
    учасники = [у["річ"] for у in опора["учасники"] if у["роль"] == "companion"]
    print("Компаньйони опори:", учасники)
    assert учасники == [комп["id"]]


if __name__ == "__main__":
    головна()
