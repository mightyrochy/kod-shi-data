# -*- coding: utf-8 -*-
"""Хвиля 2, п.2 наряду: три слова, які вікном НЕ лікуються — «хакі» (крамниці звуть ним два кольори),
«золотий»/«золото» (називає ФУРНІТУРУ, не тіло речі), «пудровий» (брудна вибірка: під словом стоять фото
інших варіантів). Питання тут одне й міряне: що САМЕ втрачає річ через це слово. Рахуємо, у скількох речей
слово ВІДКИДАЄ підтверджений вимір із фото (гілка `колір_не_вимір`) і наскільки точка тоді далі від правди.
Запуск: cd джерела && python3 проби/khvylia2_okremi_vady.py"""
import collections as К, statistics as st, sys
sys.path.insert(0, ".")
import feed, фід_каталог as FK, фід_збагачення as FZ, фід_розбір as FR, verify as V, colorspace as cs
СЛОВА = {"хакі": ("хакі",), "золотий": ("золотий", "золото"), "пудровий": ("пудровий", "powder")}
зб, н = feed.читати_збагачення(), lambda s: " ".join(str(s or "").lower().split())
кат = {r["id"]: r for r in FK._прочитати_каталог("каталог_повний.xml", 0)["каталог"]}
для = {п: g for g, ss in СЛОВА.items() for п in ss}
під = К.defaultdict(list)
for o in FR.читати_yml("каталог_повний.xml")[0]:
    п = н(o.get("колір_сирий"))
    if п not in для: continue
    z = зб.get(o["id"]) or {}; k = z.get("колір_основний") or {}
    r = кат.get(o["id"]) or {}
    if not k.get("hex") or (z.get("версія") or 1) < 2 or not FZ.колір_збагачення(z)[2].startswith("hex"): continue
    if not r.get("lab"): continue
    під[для[п]].append((o["id"], r.get("колір_джерело"), cs.de00(tuple(r["lab"]), cs.hx(k["hex"])), k["hex"]))
for g, сп in під.items():
    від = [x for x in сп if x[1] != "фото"]
    print("ФАКТ · «%s»: речей із ПІДТВЕРДЖЕНИМ виміром %d; слово відкинуло вимір у %d (%.0f%%)" % (
          g, len(сп), len(від), 100.0 * len(від) / max(len(сп), 1)))
    if від:
        print("        ΔE00 точки до правди на цих %d: медіана %.1f (якби вимір лишили — 0.0); джерела: %s" % (
              len(від), st.median(x[2] for x in від), К.Counter(x[1] for x in від).most_common()))
        print("        найдорожчі: %s" % ["%s %.0f" % (i.split("@")[0], d) for i, _, d, _ in sorted(від, key=lambda x: -x[2])[:5]])
# п.3 наряду: скільки оферів метод не бере принципово
багато, назва_лише, усього = 0, 0, 0
for o in FR.читати_yml("каталог_повний.xml")[0]:
    усього += 1
    п = н(o.get("колір_сирий"))
    if п and len(FK._СЕП_КОЛЬОРУ.split(п)) > 1: багато += 1
    elif not п and V.назва_кольору(o.get("назва") or ""): назва_лише += 1
print("ФАКТ · п.3 наряду (мовна робота, не ця хвиля): оферів усього %d; поле кольору з КІЛЬКОХ частин %d (%.0f%%); "
      "поля кольору нема, але колір є в НАЗВІ товару — %d" % (усього, багато, 100.0 * багато / усього, назва_лише))
