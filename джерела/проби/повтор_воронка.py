# -*- coding: utf-8 -*-
"""Д-1: воронка 11 828 речей каталогу → пул моделі, числа на КОЖНОМУ кроці.

Питання власника 26.09: «чому із 12 тис речей в образах часто трапляються однакові
речі». Проба ганяє справжній каталог сценою стенда (робота · офіс · 09:00 · 18 °C,
сід 4242) і друкує по слотах руки 1: каталог → абсолютні фільтри (`композитор_придатні`)
→ різних МОДЕЛЕЙ (group_id) → колірні вікна й стеля `K_НА_СЛОТ`
(`композитор_слоти._кандидати_на_слот`) → `пакет_моделі.відсікти_пул` → пул моделі
(квота семплера); остання колонка — частка каталогу слота.
Прогін: python3 проби/повтор_воронка.py      (~30 с на холодному каталозі)
"""
import collections, json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed as Ф, bridge as B, міст_пакет as МП, композитор_збирання as КЗ, pipeline as PL, композитор_слоти as КС
З, _пр, _кс, _від = {}, КЗ._придатні, КЗ._кандидати_на_слот, PL.відсікти_пул
def _придатні(речі, *а, **к):
    р = _пр(речі, *а, **к); З.setdefault("пр", (len(речі), len(р[0] if isinstance(р, tuple) else р)))
    return р
def _слот(речі, вікна, слот, *а, **к):
    р = _кс(речі, вікна, слот, *а, **к); у = [x for x in речі if x.get("слот") == слот]
    З.setdefault("сл", {}).setdefault(слот, (len(у), len({x.get("group_id") or x.get("id") for x in у}), len(р[0])))
    return р
def _відс(канд, кат, *а, **к):
    р = _від(канд, кат, *а, **к); З.setdefault("відс", {с: len(v) for с, v in (р[0] or {}).items()})
    return р
КЗ._придатні, КЗ._кандидати_на_слот, PL.відсікти_пул = _придатні, _слот, _відс
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), сід=4242)
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = collections.Counter(r.get("слот") or "—" for r in МП.каталог_останнього_пакета())
пул = {с: len(v) for с, v in [p for p in МП._КЕШ_ПАКЕТА.values() if p.get("кандидати")][0]["кандидати"].items()}
print("каталог %d речей → після абсолютних фільтрів %d (−%.0f %%); стеля K_НА_СЛОТ = %d, підлога слота = %d"
      % (З["пр"][0], З["пр"][1], 100.0 * (З["пр"][0] - З["пр"][1]) / З["пр"][0], КС.K_НА_СЛОТ, __import__("семплер").ПІДЛОГА_СЛОТА))
print("%-14s %8s %8s %8s %9s %8s %6s %7s" % ("слот", "каталог", "придатн", "моделей", "кандидат", "відсіч", "пул", "частка"))
for с, (а, м, к) in sorted(З["сл"].items(), key=lambda кв: -кв[1][0]):
    print("%-14s %8d %8d %8d %9d %8d %6d %6.1f %%" % (с, кат.get(с, 0), а, м, к, З["відс"].get(с, 0),
                                                      пул.get(с, 0), 100.0 * пул.get(с, 0) / max(кат.get(с, 1), 1)))
print("%-14s %8d %8s %8s %9d %8d %6d %6.1f %%" % ("РАЗОМ", sum(кат.values()), "", "", sum(x[2] for x in З["сл"].values()),
      sum(З["відс"].values()), sum(пул.values()), 100.0 * sum(пул.values()) / sum(кат.values())))
