import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import мова_спільне as С
М, РІШЕННЯ = С.М, ("нагода", "місце", "година", "бажання_коди", "вето_тверде", "рух", "формат", "опади")


def цитати(в, як):
    """Ті самі коди, інша цитата: `вужче` — суфікс цитати (він теж у її словах), `вигадка` — ні."""
    інша = lambda з: "так і сказала, тільки інакше" if як == "вигадка" else " ".join(з.split()[1:]) or з
    if isinstance(в, dict):
        return {к: (інша(з) if к == "quote" and isinstance(з, str) else цитати(з, як)) for к, з in в.items()}
    return [цитати(x, як) for x in в] if isinstance(в, list) else в


def паспорт(вихід, п, її):
    """Шов ходу — той самий, що в показі: внутрішня мова виходу → паспорт ядра."""
    дельта = М.прийняти_вхід("scenario", json.dumps(вихід))["внутрішня"]
    return json.loads(М.мова({"паспорт_з": дельта, "сценарій": {}, "паспорт": п, "слова_розмови": її,
                              "частини": {"need": "none", "text": "Записала."}}))["паспорт"]


рішення = lambda п: json.dumps({к: п.get(к) for к in РІШЕННЯ}, ensure_ascii=False, sort_keys=True)
ходів, руху = 0, {"вужче": 0, "вигадка": 0}
for р in json.load(open(os.path.join(С.ТУТ, "м5_розмови.json"), encoding="utf-8")):
    п, її = {}, []
    for х in р["ходи"]:
        її.append(х["вона"])
        вих = х.get("після", х.get("обидва"))
        а, ходів = паспорт(вих, п, її), ходів + 1
        for як in руху:
            руху[як] += 1 if рішення(паспорт(цитати(вих, як), п, її)) != рішення(а) else 0
        п = а
print("ходів на записах: %d · поля рішення: %s" % (ходів, ", ".join(РІШЕННЯ)))
print("цитата вужча, коди ті самі → рішення змінилось: %d з %d" % (руху["вужче"], ходів))
print("цитата вигадана → рішення змінилось: %d з %d (код не бере поля без її слів)" % (руху["вигадка"], ходів))
