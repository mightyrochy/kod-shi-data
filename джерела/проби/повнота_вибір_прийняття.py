"""5238: адреса гейту не росте від реплік; why не переходить на нову заборонену річ."""
import sys, pathlib, json
sys.path.insert(0, sys.argv[1] if len(sys.argv) > 1 else str(pathlib.Path(__file__).resolve().parents[1]))
import формальність as Ф, вердикт_моделі as В, повнота_образу as П


def головна():
    """Друкує факти чинного емітента, повторного вибору і суду зміненого складу."""
    речі = [dict(id=і, річ=і, назва=т, тип=т, слот=с, ошатність=р)
            for і, т, с, р in [('а', 'кардиган', 'верх', 5), ('б', 'човники', 'взуття', 6),
                              ('в', 'штани', 'низ', 6), ('г', 'кеди', 'взуття', 1)]]
    пул = {с: [р for р in речі if р['слот'] == с] for с in {р['слот'] for р in речі}}
    def образ(ід, номер='о1'):
        """Судить склад справжніми емітентами формальності й будівником вердикту."""
        е = [р for р in речі if р['id'] in ід]
        з, _ = В.знахідки_вердикту(Ф.вимоги_коду(е, 'cocktail')
                                    + Ф.формальність_образу(е, {'діапазон': (7, 8)}), номер)
        return dict(ід=номер, речі=ід, знахідки=з, структура=dict(ок=False, блокери=[dict(код='no_top_and_bottom')]))
    був = образ(['а', 'б'], 'о3'); гейт = next(z for z in був['знахідки'] if z['регістр'] == 'гейт')
    def спроба(ід, знахідка=None, чому='Свідомо лишаю ансамбль без сукні'):
        """Проводить сирий вибір через перенос прийняття і CQ06."""
        вибір = dict(текст=json.dumps(dict(version='1', chosen='o3', accept=[dict(finding=знахідка or гейт['ід'], why=чому)])), вердикт=dict(образи=[був]))
        в = dict(образи=[образ(ід)])
        if hasattr(П, 'донести_прийняття_вибору'): П.донести_прийняття_вибору(в, вибір, пул, речі)
        к = в['образи'][0]; сл, н = П._словник_речей(пул, речі), П._за_номером(пул)
        суд = П._суд_складу(к, ід, П._свідомі_ключі(к, ід, сл, н), [], сл, н)
        з = next(z for z in суд['знахідки'] if z['регістр'] == 'гейт'); return з.get('прийнято_чому') or з.get('свідомий')
    факти = dict(той_самий=спроба(['а', 'б', 'в']), чуже_взуття=спроба(['а', 'б', 'в', 'г']),
                 чужа_знахідка=спроба(['а', 'б', 'в'], 'з-о9-9'), без_чому=спроба(['а', 'б', 'в'], чому=''),
                 число_чому=спроба(['а', 'б', 'в'], чому=37), булеве_чому=спроба(['а', 'б', 'в'], чому=True),
                 обʼєкт_чому=спроба(['а', 'б', 'в'], чому={'x': 1}),
                 список_чому=спроба(['а', 'б', 'в'], чому=['why']), вкладений_список_чому=спроба(['а', 'б', 'в'], чому=[['why']]),
                 null_чому=спроба(['а', 'б', 'в'], чому=None), список_обʼєктів_чому=спроба(['а', 'б', 'в'], чому=[{'why': 'x'}]),
                 інший_образ=спроба(['а', 'в']))
    print(json.dumps(dict(контекст=гейт['речі'], адреса_гейту=гейт.get('гейт_речі'), **факти), ensure_ascii=False))
    return 0 if факти['той_самий'] == 'Свідомо лишаю ансамбль без сукні' and not any(v for k, v in факти.items() if k != 'той_самий') else 1


if __name__ == '__main__':
    sys.exit(головна())
