"""НП-в крок 2: смуга ошатності — лише відповідь мовної моделі. Друкує на 6 нагодах смугу пулу з відповіді моделі
кодом щабля драбини (3.7-Б, рядок 8970: доти — число з таблиці заглушки `СТЕНД_ОШАТНІСТЬ_НАГОДИ`, знятої з
`рв6_стенд.js`, рядок 8951) і з пари через два щаблі, яку код зводить до одного щабля; і плитку без розмови: до
НП-в5 — шов із порожньою дельтою (числа нема), після — хід плиток мовної моделі (показ `паспортШаромП`: дельта —
лише норма події без цитати, слів нема). Запуск із `джерела`: python3 проби/нагода_смуга_числом.py"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import мовний_шар as МШ, сценарій as СЦ, композитор_придатні as КП
# відповідь моделі на дроті (код щабля) і пара через два щаблі, яку вона могла дати доти
for ключ, код, щабель, пара in (("робота", "work", "neat", [5, 7]), ("співбесіда", "job_interview", "smart", [7, 8]),
                                ("весілля_гість", "wedding_guest", "smart", [7, 9]), ("траур", "mourning", "neat", [5, 7]),
                                ("театр", "theatre", "neat", [4, 6]), ("прогулянка", "walk", "everyday", [2, 4])):
    ф = МШ._смуга_числом({"formality": щабель})[0]["formality"]
    ч = [ф["from"], ф["to"]]
    print("%-14s пара %s → %s" % (ключ, пара, МШ._смуга_числом({"formality": {"from": пара[0], "to": пара[1]}})[0]["formality"]))
    п = МШ.паспорт_з_шару({"occasion": код, "formality": {"from": ч[0], "to": ч[1]}}, {"нагода": ключ}, None, {})["паспорт"]
    сц = СЦ.з_показу({"нагода": ключ}, п)[0]
    до = МШ.паспорт_з_шару({}, {"нагода": ключ}, None, {}, слова_ходу=[])["паспорт"]
    хід = МШ.паспорт_з_шару({"formality": {"from": ч[0], "to": ч[1]}}, {"нагода": ключ}, None, {}, слова_ходу=[])["паспорт"]
    print("%-14s щабель моделі %s → смуга пулу %s · плитка без розмови: порожня дельта → %s, хід плиток → %s"
          % (ключ, щабель, КП.смуга_нагоди(сц), КП.смуга_нагоди(СЦ.з_показу({"нагода": ключ}, до)[0]),
             КП.смуга_нагоди(СЦ.з_показу({"нагода": ключ}, хід)[0])))
print("ПОЛЕ event_formality у схемі розмови:", "event_formality" in МШ._ВМ.СЦЕНАРІЙ)
