"""НП-в крок 2: смуга ошатності — лише число мовної моделі. Друкує на 6 нагодах смугу пулу з числа,
яке ставить заглушка стенда (`рв6_стенд.js` СТЕНД_ОШАТНІСТЬ_НАГОДИ), і смугу тієї самої сцени без
числа (плитка без розмови до кроку 3). Запуск із `джерела`: python3 проби/нагода_смуга_числом.py"""
import sys, os, re, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import мовний_шар as МШ, сценарій as СЦ, композитор_придатні as КП
js = open("../аудит/проби/рв6_стенд.js", encoding="utf-8").read()
таб = json.loads(re.sub(r"(\w+):", r'"\1":', re.search(r"СТЕНД_ОШАТНІСТЬ_НАГОДИ = (\{.*?\});", js, re.S).group(1)))
for ключ, код in (("робота", "work"), ("співбесіда", "job_interview"), ("весілля_гість", "wedding_guest"),
                  ("траур", "mourning"), ("театр", "theatre"), ("прогулянка", "walk")):
    ч = таб[код]
    п = МШ.паспорт_з_шару({"occasion": код, "formality": {"from": ч[0], "to": ч[1]}}, {"нагода": ключ}, None, {})["паспорт"]
    сц = СЦ.з_показу({"нагода": ключ}, п)[0]
    print("%-14s число моделі %s → смуга пулу %s · без числа → %s"
          % (ключ, ч, КП.смуга_нагоди(сц), КП.смуга_нагоди({"нагода": ключ})))
print("ПОЛЕ event_formality у схемі розмови:", "event_formality" in МШ._ВМ.СЦЕНАРІЙ)
