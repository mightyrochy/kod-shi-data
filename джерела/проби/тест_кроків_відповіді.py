"""Звірки трьох кроків відповіді на записі с5 з четвертого живого прогону."""
import gzip
import json
from pathlib import Path
from unittest import TestCase, main

import міст_відповіді as міст

ДЖЕРЕЛА = Path(__file__).resolve().parents[1]
СЦЕНА = (ДЖЕРЕЛА.parent / "аудит/проби/живий-як-людина-4/стенд/службове"
         / "с5_весілля_сестри")


def _запис_опису():
    """Повертає запит, відповідь і зафіксовану після них картку руки 1."""
    with gzip.open(СЦЕНА / "обміни.jsonl.gz", "rt", encoding="utf-8") as записи:
        обмін = next(json.loads(рядок) for рядок in записи if "its creamy near-white shade" in рядок)
    блоки = json.loads(обмін["запит"])["messages"][-1]["content"]
    запит = json.loads(next(б["text"] for б in блоки if б.get("text", "").startswith('{"version":')))
    відповідь = json.loads(обмін["відповідь"])["content"][0]["text"]
    with (СЦЕНА / "руки.jsonl").open(encoding="utf-8") as записи:
        кадр = next(к for к in map(json.loads, записи) if к["прохід"] == 1 and к["крок"] == 80)
    картка = next(к for к in кадр["позиції"] if к["рука"] == "1")
    return запит, відповідь, картка


def _вхід_кроків():
    """Відновлює склад і номери з картки та запиту, а тіло бере зі стенда."""
    запит, текст, картка = _запис_опису()
    записи = []
    кандидати = {}
    for річ, дані, вхід in zip(картка["речі"], картка["дані_речей"], запит["outfit"]["items"], strict=True):
        номер, крамниця = вхід["n"].removeprefix("#").split("·")
        запис = dict(id=дані["ід"], слот=річ["слот"], назва=річ["назва"], hex=вхід["hex"],
                     за_запитом=True, _номер_за_запитом=(int(номер), крамниця))
        записи.append(запис)
        кандидати.setdefault(річ["слот"], []).append(запис)
    вхід = dict(ід=[р["id"] for р in записи], відповідь="ОПИС_ВІДПОВІДЬ_V1", текст_моделі=текст)
    F, T, _, _ = міст._збірка(json.loads((ДЖЕРЕЛА / "стенд_вх.json").read_text(encoding="utf-8")))
    контекст = міст._КонтекстСуду(
        F, T, {"палітри": {"розвилка": []}}, None, None, "conventional",
        {"кандидати": кандидати, "_каталог": записи}, False, False, set(), None, None, None)
    return вхід, контекст, картка


def _розібрати_запис(вхід, пак):
    """Передає кроку розбору ідентифікатори записаного складу опису."""
    ід = вхід["ід"]
    return міст._розібрати_відповідь(вхід, пак, вхід["відповідь"], None, ід, ід)


class КрокиВідповіді(TestCase):
    """Кожен крок можна викликати з його власним входом."""

    def test_розбір_називає_поле_і_причину(self):
        """Поради з запису прочитано, зіпсовані поради дають помилку схеми."""
        вхід, контекст, _ = _вхід_кроків()
        розбір = _розібрати_запис(вхід, контекст.пак)
        self.assertEqual(розбір.ід_образу, вхід["ід"])
        self.assertTrue(розбір.опис["як_носити"])
        хибний = dict(json.loads(вхід["текст_моделі"]), how_to_wear="this is not a list")
        розбір = _розібрати_запис(dict(вхід, текст_моделі=json.dumps(хибний)), контекст.пак)
        self.assertTrue(any(п["де"] == "як_носити" and "need=list" in п["що"]
                            for п in розбір.опис["помилки"]), розбір.опис["помилки"])

    def test_суд_зіставляє_записану_річ_і_причину(self):
        """Суд бачить річ картки й відмовляє заміні з підставою поза переліком."""
        вхід, контекст, _ = _вхід_кроків()
        for підстава, стан, відмова in (
            ("colour", "no_spares", None),
            (json.loads(вхід["текст_моделі"])["swap"]["why"], "refused", "reason_not_in_list"),
        ):
            with self.subTest(стан=стан):
                текст = json.loads(вхід["текст_моделі"])
                текст["swap"]["why"] = підстава
                дані = dict(вхід, текст_моделі=json.dumps(текст))
                розбір = _розібрати_запис(дані, контекст.пак)
                міст.СЛ.почати()
                прогін = міст._ПОЛ.прогін()
                первинний = міст._P.перевірити_від_моделі(
                    розбір.ід_образу, контекст.F, контекст.пак["_каталог"], контекст.T, {},
                    кандидати=контекст.пак["кандидати"], текст_моделі=розбір.вхід["текст_моделі"],
                    прогін_руки=прогін)
                суд = міст._судити_склад(розбір, контекст, {}, None, прогін, первинний)
                заміна = суд.вердикт["заміна"]
                self.assertEqual(заміна["річ"], "ж-01590@brenda.ua")
                self.assertEqual((заміна["стан"], заміна.get("відмова")), (стан, відмова))
                self.assertEqual([р["id"] for р in суд.вердикт["речі"]], вхід["ід"])

    def test_результат_зберігає_пораду_і_діагноз(self):
        """Результат містить поради або діагноз схеми зі збереженим складом."""
        вхід, контекст, картка = _вхід_кроків()
        self.assertIn("Я замінюю сукню", картка["текст_картки"])
        for зіпсовано in (False, True):
            with self.subTest(зіпсовано=зіпсовано):
                текст = json.loads(вхід["текст_моделі"])
                if зіпсовано:
                    текст["how_to_wear"] = "this is not a list"
                розбір = _розібрати_запис(dict(вхід, текст_моделі=json.dumps(текст)), контекст.пак)
                вердикт = {
                    "речі": контекст.пак["_каталог"],
                    "опис": розбір.опис,
                    "заміна": {"стан": "refused", "відмова": "reason_not_in_list"},
                }
                суд = міст._СудженаВідповідь(розбір.вхід, вердикт, 1, None)
                міст.СЛ.почати()
                результат = json.loads(міст._підготувати_результат(
                    суд, розбір, контекст, {}, {}, None, міст._ПОЛ.прогін()))
                self.assertEqual([р["id"] for р in результат["речі"]], вхід["ід"])
                self.assertEqual(результат["заміна"]["відмова"], "reason_not_in_list")
                if зіпсовано:
                    self.assertTrue(any(п["де"] == "як_носити" and "need=list" in п["що"]
                                        for п in результат["опис"]["помилки"]))
                else:
                    self.assertEqual(результат["опис"]["як_носити"], текст["how_to_wear"])


if __name__ == "__main__":
    main()
