"""Звірки трьох кроків відповіді на записі с5 з четвертого живого прогону."""
import json
from pathlib import Path
from types import SimpleNamespace
from unittest import TestCase, main

import міст_відповіді as міст

ДЖЕРЕЛА = Path(__file__).resolve().parents[1]
# Свідок 15983. Четвертий живий прогін, с5, прохід 1: обмін 16, картка руки 1 з кадру 80.
ЗАПИС = Path(__file__).resolve().parent / "протокол" / "відповідь_с5" / "опис.json"


def _вхід_кроків():
    """Відновлює склад і номери з картки та запиту, а тіло бере зі стенда."""
    дані = json.loads(ЗАПИС.read_text(encoding="utf-8"))
    картка = дані["картка"]
    записи = []
    кандидати = {}
    for річ, вхід in zip(картка["речі"], дані["запит_склад"]["items"], strict=True):
        номер, крамниця = вхід["n"].removeprefix("#").split("·")
        запис = dict(id=річ["ід"], слот=річ["слот"], назва=річ["назва"], hex=вхід["hex"],
                     за_запитом=True, _номер_за_запитом=(int(номер), крамниця))
        записи.append(запис)
        кандидати.setdefault(річ["слот"], []).append(запис)
    вхід = dict(ід=[р["id"] for р in записи], відповідь="ОПИС_ВІДПОВІДЬ_V1", текст_моделі=дані["відповідь"])
    F, T, _, _ = міст._збірка(json.loads((ДЖЕРЕЛА / "стенд_вх.json").read_text(encoding="utf-8")))
    контекст = міст._КонтекстСуду(
        F, T, {"палітри": {"розвилка": []}}, None, None, "conventional",
        {"кандидати": кандидати, "_каталог": записи}, False, False, set(), None, None, None)
    return вхід, контекст, картка


def _розібрати_запис(вхід, пак):
    """Передає кроку розбору ідентифікатори записаного складу опису."""
    ід = вхід["ід"]
    return міст._розібрати_відповідь(вхід, пак, вхід["відповідь"], None, ід, ід)


class КрокиВідповіді(TestCase):
    """Кожен крок можна викликати з його власним входом."""

    def test_розбір_називає_поле_і_причину(self):
        """Поради з запису прочитано, зіпсовані поради дають помилку схеми."""
        вхід, контекст, _ = _вхід_кроків()
        розбір = _розібрати_запис(вхід, контекст.пак)
        self.assertEqual(розбір.ід_образу, вхід["ід"])
        self.assertTrue(розбір.опис["як_носити"])
        хибний = dict(json.loads(вхід["текст_моделі"]), how_to_wear="this is not a list")
        розбір = _розібрати_запис(dict(вхід, текст_моделі=json.dumps(хибний)), контекст.пак)
        self.assertTrue(any(п["де"] == "як_носити" and "need=list" in п["що"]
                            for п in розбір.опис["помилки"]), розбір.опис["помилки"])

    def test_суд_зіставляє_записану_річ_і_причину(self):
        """Суд бачить річ картки й відмовляє заміні з підставою поза переліком."""
        вхід, контекст, _ = _вхід_кроків()
        for підстава, стан, відмова in (
            ("colour", "no_spares", None),
            (json.loads(вхід["текст_моделі"])["swap"]["why"], "refused", "reason_not_in_list"),
        ):
            with self.subTest(стан=стан):
                текст = json.loads(вхід["текст_моделі"])
                текст["swap"]["why"] = підстава
                дані = dict(вхід, текст_моделі=json.dumps(текст))
                розбір = _розібрати_запис(дані, контекст.пак)
                міст.СЛ.почати()
                прогін = міст._ПОЛ.прогін()
                первинний = міст._P.перевірити_від_моделі(
                    розбір.ід_образу, контекст.F, контекст.пак["_каталог"], контекст.T, {},
                    кандидати=контекст.пак["кандидати"], текст_моделі=розбір.вхід["текст_моделі"],
                    прогін_руки=прогін)
                дані_суду, вердикт = міст._судити_набір(розбір, контекст, {}, прогін, первинний)
                суд = міст._судити_склад(дані_суду, вердикт, розбір, контекст, {}, None, прогін, 1)
                заміна = суд.вердикт["заміна"]
                self.assertEqual(заміна["річ"], "ж-01590@brenda.ua")
                self.assertEqual((заміна["стан"], заміна.get("відмова")), (стан, відмова))
                self.assertEqual([р["id"] for р in суд.вердикт["речі"]], вхід["ід"])

    def test_результат_зберігає_пораду_і_діагноз(self):
        """Склад картки — запит опису; проза опису, що пропонував заміну, на картку не йде; зіпсована — діагноз."""
        вхід, контекст, картка = _вхід_кроків()
        self.assertIn("Я замінюю сукню", картка["текст"])
        for зіпсовано, із_заміною in ((False, True), (True, True), (False, False)):
            with self.subTest(зіпсовано=зіпсовано, із_заміною=із_заміною):
                текст = json.loads(вхід["текст_моделі"])
                if зіпсовано:
                    текст["how_to_wear"] = "this is not a list"
                if not із_заміною:
                    текст.pop("swap")
                розбір = _розібрати_запис(dict(вхід, текст_моделі=json.dumps(текст)), контекст.пак)
                вердикт = {
                    "речі": контекст.пак["_каталог"],
                    "опис": розбір.опис,
                    "заміна": {"стан": "refused", "відмова": "reason_not_in_list"},
                }
                суд = міст._СудженаВідповідь(розбір.вхід, вердикт, 1, None,
                                              міст._остаточний_склад(вердикт, розбір, контекст.пак))
                міст.СЛ.почати()
                результат = json.loads(міст._підготувати_результат(
                    суд, розбір, контекст, {}, {}, None, міст._ПОЛ.прогін()))
                self.assertEqual([р["id"] for р in результат["речі"]], вхід["ід"])
                self.assertEqual(результат["склад_картки"]["ід"], вхід["ід"])
                self.assertEqual(set(результат["склад_картки"]["джерела"].values()), {"request"})
                self.assertEqual(результат["заміна"]["відмова"], "reason_not_in_list")
                if зіпсовано:
                    self.assertTrue(any(п["де"] == "як_носити" and "need=list" in п["що"]
                                        for п in результат["опис"]["помилки"]))
                if із_заміною:
                    # 15983: «Я замінюю сукню» під тією самою сукнею — проза писала інший склад
                    self.assertIsNone(результат["опис"]["текст"])
                    self.assertEqual(результат["опис"]["як_носити"], [])
                    self.assertEqual(результат["опис"]["не_для_картки"]["чому"], "swap_proposed")
                    self.assertEqual(результат["опис"]["не_для_картки"]["склад"], вхід["ід"])
                else:
                    self.assertEqual(результат["опис"]["як_носити"], текст["how_to_wear"])
                    self.assertNotIn("не_для_картки", результат["опис"])


_ОБРАЗ = SimpleNamespace(опис=None, ід_образу=None, частини=None, місця=None)
_ВЕРХ = dict(id="в1@s", слот="верх", назва="Светр", частина_комплекту="top")
_НИЗ = dict(id="н1@s", слот="низ", назва="Спідниця")
_ЧУЖА = dict(id="ч1@s", слот="верх", назва="Блуза з іншого образу")
_ЗАМША = dict(id="з1@s", слот="взуття", назва="Чоботи замшеві", матеріал="замша", склад="натуральна замша")


class ОстаточнийСклад(TestCase):
    """Крок 2 віддає один склад картки, з якого крок 3 бере все — і поради, і вхід опису."""

    def test_склад_повноти_з_дібраною_кодом_річчю(self):
        """Річ, яку дібрав код, — у складі й джерелах; річ чужого образу — ні; половини й місця — лише складу."""
        в = dict(речі=[_ВЕРХ, _ЧУЖА], повнота=dict(
            ід=["в1@s", "н1@s", "з1@s"], повний=True, образ="о2", дібрані=[{"id": "з1@s"}, "сміття"],
            частини={"н1@s": "bottom", "ч1@s": "top"}, місця={"ч1@s": "office"}))
        склад = міст._остаточний_склад(в, _ОБРАЗ, {"_каталог": [_НИЗ, _ЗАМША, _ЧУЖА]})
        self.assertEqual(склад.ід, ("в1@s", "н1@s", "з1@s"))
        self.assertEqual([р["id"] for р in склад.речі], ["в1@s", "н1@s", "з1@s"])
        self.assertEqual(склад.джерела, {"в1@s": "model", "н1@s": "model", "з1@s": "code_added"})
        self.assertEqual(склад.частини, {"н1@s": "bottom", "в1@s": "top"})
        self.assertEqual(склад.місця, {})
        self.assertEqual((склад.образ, склад.прийнято), ("о2", True))
        self.assertEqual(json.loads(json.dumps(склад.на_дріт()))["ід"], ["в1@s", "н1@s", "з1@s"])

    def test_зіпсовані_записи(self):
        """Нема повноти — склад верхнього образу; речі без id і невідомі каталогу не падають і не губляться."""
        склад = міст._остаточний_склад(dict(речі=[_ВЕРХ, {"слот": "низ"}], повнота=None), _ОБРАЗ, {})
        self.assertEqual((склад.ід, склад.прийнято), (("в1@s",), False))
        склад = міст._остаточний_склад(dict(речі=None, повнота=dict(ід=["х@s"], дібрані=None)), _ОБРАЗ,
                                         {"_каталог": [{"слот": "верх"}]})
        self.assertEqual((склад.ід, склад.речі), (("х@s",), ({"id": "х@s"},)))

    def test_прийнята_заміна_позначає_річ(self):
        """Повторний суд після прийнятої заміни: річ заміни — `swap`; зіпсований склад картки не падає."""
        склад = міст._остаточний_склад(dict(речі=[_ВЕРХ, _НИЗ], повнота=dict(ід=["в1@s", "н1@s"])), _ОБРАЗ, {})
        нове = міст._позначити_заміну(dict(склад_картки=склад.на_дріт()), dict(стан="accepted", на="н1@s"))
        self.assertEqual(нове["склад_картки"]["джерела"], {"в1@s": "model", "н1@s": "swap"})
        self.assertEqual(нове["заміна"]["стан"], "accepted")
        for зіпсоване in ({}, {"склад_картки": None}, {"склад_картки": {"джерела": None}}):
            with self.subTest(зіпсоване=зіпсоване):
                нове = міст._позначити_заміну(dict(зіпсоване), dict(стан="accepted", на="х@s"))
                self.assertEqual(нове["заміна"]["на"], "х@s")

    def test_порада_картки_про_річ_коду(self):
        """Контрольна 16227 і стара вада картки: замша, яку дібрав код, — у пораді; сіль — з погоди, не з її слова."""
        в = dict(речі=[_ВЕРХ, _НИЗ], повнота=dict(ід=["в1@s", "н1@s", "з1@s"], дібрані=[{"id": "з1@s"}]))
        пак = {"_каталог": [_ВЕРХ, _НИЗ, _ЗАМША]}
        склад = міст._остаточний_склад(в, _ОБРАЗ, пак)
        за_ід = {р["id"]: р for р in пак["_каталог"]}
        сцен = dict(смуга_погоди="frost", опади="сніг")
        старий = [р for р in в["речі"] if р["id"] in set(в["повнота"]["ід"])]
        міст._поради_для_картки(в, пак, сцен, старий, за_ід, міст._ПОЛ.прогін())
        self.assertNotIn("матеріал_жінці", в)
        міст._поради_для_картки(в, пак, сцен, list(склад.речі), за_ід, міст._ПОЛ.прогін())
        self.assertEqual((в["матеріал_жінці"]["сіль"], в["матеріал_жінці"]["сіль_звідки"]), (True, "weather"))
        заява = в["матеріал_жінці"]["повідомлення"]["statements"][0]
        self.assertEqual(заява["code"], "material_on_salted_road")
        # її слово «реагентів нема» сильніше за погоду: сухий сніг без солі замші не псує — рядка нема
        в_без_солі = {к: v for к, v in в.items() if к != "матеріал_жінці"}
        міст._поради_для_картки(в_без_солі, пак, dict(сцен, реагенти="ні"), list(склад.речі), за_ід,
                                 міст._ПОЛ.прогін())
        self.assertNotIn("матеріал_жінці", в_без_солі)


