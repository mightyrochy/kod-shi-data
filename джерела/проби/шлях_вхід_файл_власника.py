"""Розбір 1/8 (вхід і сценарій): ЩО ЇЇ, А ЩО ТЯГНЕТЬСЯ З МИНУЛОГО СЦЕНАРІЮ — на файлах вердиктів
власника 25.09. Для кожного прогону друкує її репліки, поля сценарію з ВХІД-V1, поля паспорта,
`джерело_полів` і чи є в її словах хоч одне слово про годину, погоду й живіт. Факт: нагода, місце,
година, температура й чип «живіт» однакові в прогонах 22, 24 і 25.09, а слова щоразу інші.
Запуск із теки `джерела`: `python3 проби/шлях_вхід_файл_власника.py`."""
import sys, os, json, re
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import паспорт_нагоди as ПН

тека = "../аудит/тести/власник_2026-09-25"
for назва in ("verdykty-0phxvk-2026-09-25-1953.json", "verdykty-0phxvk-2026-09-25-2012.json"):
    д = json.load(open(os.path.join(тека, назва), encoding="utf-8"))
    print("\n══ %s · прогонів %s, вердиктів %s" % (назва, д["прогонів"], д["вердиктів"]))
    for пр in д["прогони"]:
        с = пр["спільне"]; п = с.get("паспорт") or {}; в = (с.get("вхід_прогону") or {})
        її = " ".join(str(р.get("текст") or "") for р in (с.get("чат") or []) if р.get("хто") == "людина")
        print(" %s %s | її слова: «%s»" % (с.get("дата"), с.get("розклад"), її[:70] or "розмови не було"))
        print("   ВХІД-V1 сценарій: %s | слова=%r"
              % (json.dumps(в.get("сценарій"), ensure_ascii=False) if в else "поля нема (стара збірка)",
                 (в.get("слова") if в else None)))
        print("   паспорт: нагода=%s місце=%s дрес=%s ошатність=%s година=%s темп=%s подія=«%s» слова=%r шаром=%s"
              % (п.get("нагода"), п.get("місце"), п.get("дрес_код"), п.get("ошатність"), п.get("година"),
                 п.get("темп_c"), п.get("подія"), п.get("слова"), п.get("перекладено_шаром")))
        print("   джерело_полів=%s | зони_чипами=%s | вето.зони=%s"
              % (json.dumps(п.get("джерело_полів"), ensure_ascii=False), п.get("зони_чипами"),
                 (п.get("вето") or {}).get("зони")))
        print("   у її словах: про годину %s, про погоду %s, про живіт %s"
              % (ПН.сказано_про("година", її) if її else "слів нема",
                 (ПН.темп_зі_слів(її) is not None) if її else "слів нема",
                 bool(re.search(r"живіт|живот", її, re.I))))
