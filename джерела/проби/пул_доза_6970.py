# -*- coding: utf-8 -*-
"""Доза 6970/6972: три сцени через справжні «запити», каталог → вікна → пул; без моделі."""
import os, sys, json, collections
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def проба():
    """Друкує факти дозування на повному каталозі й незмінних входах стенда."""
    os.chdir(sys.path[0])
    import bridge as Б, feed as Ф, композитор_збирання as КЗ
    каталог = Ф.каталог_на_диску("каталог_повний.xml")
    база = json.load(open("стенд_вх.json", encoding="utf-8"))
    журнал, стара = {}, КЗ._кандидати_на_слот
    def кандидати(*а, **к):
        """Зберігає перший (рука 1) фактичний перехід суконь крізь вікна."""
        р = стара(*а, **к)
        if а[2] == "сукня" and not журнал:
            сукні = [х for х in а[0] if х.get("слот") == "сукня"]
            журнал.update(каталог=len(а[0]), сукня_до=[len(сукні), sum((х.get("блиск") or 0) >= 2 for х in сукні)],
                          сукня_вікна=[len(р[0]), sum((х.get("блиск") or 0) >= 2 for х in р[0])])
        return р
    КЗ._кандидати_на_слот = кандидати
    сцени = [("співбесіда", dict(нагода="співбесіда", місце="офіс", година=9, темп_c=18, дрес_код="business_casual"), [5, 6]),
             ("весілля", dict(нагода="весілля_гість", місце="весілля_вечірнє", година=17, темп_c=18), [6, 8]),
             ("вечір14.10", dict(нагода="побачення", місце="ресторан_районний", дрес_код="smart_casual", година=19, темп_c=18, опади="дощ", мета="лестити"), [4, 6])]
    for назва, сцена, смуга in сцени:
        журнал.clear()
        р = json.loads(Б.виклик("запити", json.dumps(dict(база, каталог=каталог, сценарій=сцена,
            паспорт=dict(сцена, ошатність=смуга), випадок=назва), ensure_ascii=False)))
        пул = р["кандидати"]; сукні = пул.get("сукня") or []
        print(json.dumps(dict(сцена=назва, **журнал, пул=р["пул_речей"],
            нижче=sum(bool(х.get("_нижче_смуги")) for в in пул.values() for х in в),
            сукня_пул=[len(сукні), sum((х.get("блиск") or 0) >= 2 for х in сукні)],
            слоти={с: len(в) for с, в in пул.items()}, гілки=dict(collections.Counter(х.get("гілка") for в in пул.values() for х in в)),
            токени=р["стеля"].get("пул_токенів"), бюджет=р["стеля"].get("бюджет")), ensure_ascii=False), flush=True)


if __name__ == "__main__":
    проба()
