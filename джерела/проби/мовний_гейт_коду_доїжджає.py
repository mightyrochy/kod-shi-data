# -*- coding: utf-8 -*-
"""Проба: чи доїжджає до показу те, що мовний гейт знайшов у НАШОМУ тексті.

Писар (`language_gate.перевірити_знахідки`) кладе брудні під ключем `деталі`;
`bridge` читав `брудні` — ключ, якого там нема, тож `чисто` виходило True завжди.

Прогін: cd джерела && python3 проби/мовний_гейт_коду_доїжджає.py
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import language_gate as МГ

# Знахідка з ремонтом, який порушує анти-правило корпусу (R-ONB-06: «приховає»).
знахідки = [dict(правило="K-SIL-06", суть="пропорція верху й низу",
                 чому="лінія талії губиться",
                 ремонт=["ця спідниця сховає ваду в зоні живота"])]
мгк = МГ.перевірити_знахідки(знахідки)
print("писар віддає ключі: %s" % sorted(мгк))
print("  брудних=%s  чисто=%s  len(деталі)=%d"
      % (мгк["брудних"], мгк["чисто"], len(мгк["деталі"])))
print("  СТАРЕ читання _мгк.get('брудні') -> %r  => чисто=%s, брудних=%d"
      % (мгк.get("брудні"), not (мгк.get("брудні") or []), len(мгк.get("брудні") or [])))

# Те саме місце `bridge`, дослівно (після правки).
_брудні = мгк.get("деталі") or []
вихід = dict(чисто=мгк.get("чисто", not _брудні),
             брудних=мгк.get("брудних", len(_брудні)),
             правила=[dict(правило=x.get("правило"),
                           порушення=[y.get("правило") for y in
                                      ((x.get("вердикт") or {}).get("порушення") or [])])
                      for x in _брудні][:6])
print("  НОВЕ читання _мгк.get('деталі')  => чисто=%s, брудних=%d, правила=%s"
      % (вихід["чисто"], вихід["брудних"], вихід["правила"]))
assert вихід["брудних"] == мгк["брудних"], "лічба розійшлась із писарем"
print("ФАКТ: гейт знайшов %d, до показу тепер доїжджає %d (доти доїжджало 0)"
      % (мгк["брудних"], вихід["брудних"]))
