# -*- coding: utf-8 -*-
"""K-PAL-06 (нейтраль плюс акцент) — умова прийому судить образ.

Корпус (тема-2:1852): «нейтралі людини + один акцент, перший — сім'я очей; дефолт
для високого контрасту; ДЛЯ НИЗЬКОГО АКЦЕНТ ПРИГЛУШЕНИЙ». Умова стояла в полі
`коли` й нікого не судила: образ «три нейтралі + гучна пляма» на
низькоконтрастній жінці проходив мовчки.
ПІСЛЯ: коли образ саме такий (решта нейтралі, кольоровий один), гучність акценту
міряється проти рівня контрасту людини. Гучна річ береться з КАТАЛОГУ: у пулі її
після правки вікон палітри може не бути, а модель назвати таку річ може.
Запуск із теки `джерела`: `python3 проби/pal_K-PAL-06.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import pipeline as PL, реєстр_правил as РП

вх, r, кат, спец = ПВ.стенд(гілка=0)
гучно = РП.C["hi_C"]
рівень = спец["палітра_практична"]["контраст_рівень"]
нейтраль = lambda L, C, h, _: PL._нейтральний_тон(h, C, L)
гучний = lambda L, C, h, _: not PL._нейтральний_тон(h, C, L) and C >= гучно
акц = ПВ.з_каталогу(кат, "верх", гучний) or ПВ.з_каталогу(кат, "сукня", гучний)
нейтралі = [x for x in (ПВ.взяти(r, кат, с, нейтраль) for с in ("низ", "взуття", "сумка")) if x]
print("контраст людини «%s» · акцент із каталогу: %s (хрома %.0f, поріг гучного %.0f) · "
      "нейтралей поруч %d"
      % (рівень, ((акц or {}).get("назва") or "нема")[:28],
         ПВ.lch(кат, акц["id"])[1] if акц else 0.0, гучно, len(нейтралі)))
if not акц or len(нейтралі) < 2:
    print("ФАКТ · образу «нейтралі + один гучний акцент» не скласти"); raise SystemExit(0)
зн, _ = ПВ.знахідки(вх, [x["id"] for x in [акц] + нейтралі][:4])
print("ФАКТ · K-PAL-06: %s" % ПВ.рядок(зн, "K-PAL-06"))
z = next((x for x in зн if x.get("правило") == "K-PAL-06"), None)
assert bool(z) == (рівень == "низький"), (bool(z), рівень)
if z: print("       ремонт: %s" % z["ремонт"])
