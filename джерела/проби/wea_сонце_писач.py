"""Друкує шлях прямого сонця: слова → розбір моделі → паспорт → суд і дріт."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import мовний_шар as М, паспорт_нагоди as П, сценарій as С, суд_образу as Суд
import дріт_моделі as Д


if __name__ == "__main__":
    for код, слова, значення in (("yes", "Буду під прямим сонцем", True),
                                ("no", "Буду в тіні", False),
                                ("unknown", "Екскурсія, +12 °C, без дощу", None)):
        відповідь = М.прийняти_розмову(json.dumps({"update": {
            "direct_sun": {"value": код, "quote": слова if значення is not None else ""}},
            "text": "Записала", "need": "none"}, ensure_ascii=False))
        паспорт = М.паспорт_з_шару(відповідь["внутрішня"], {}, слова_ходу=[слова])["паспорт"]
        нагода, _ = П.з_показу({}, паспорт)
        assert нагода.get("сонце") is значення, (код, паспорт, нагода)
        дріт = С.день_кодами(нагода)
        assert ("direct_sun" in дріт) == (значення is not None)
        if значення is not None:
            assert дріт["direct_sun"] is значення
            assert М.паспорт_кодами(паспорт)["direct_sun"] == код
            assert Д.випадок({"сонце": значення})["direct_sun"] is значення
            assert "direct_sun" not in Д.випадок({"сонце": значення}, день=дріт)
        ч = Суд.чеклісти([], [], сонце=нагода.get("сонце"))
        пункт = next(п for п in ч["надлишок"] if п["пункт"] == 21)
        assert пункт["стан"] == ("без входу" if значення is None else "пройдено"), пункт
        if значення is None:
            assert пункт["бракує"][0]["fields"] == ["сонце"]
        знахідки = Суд.погода([], стан="надворі", сонце=нагода.get("сонце"))
        брак = [з for з in знахідки if з["правило"] == "K-WEA-03" and з.get("без_входу")]
        assert bool(брак) == (значення is None), знахідки
        print(код, "→", нагода.get("сонце"), "→", пункт["стан"], пункт.get("чому", ""))
