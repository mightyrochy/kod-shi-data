"""Розбір шляху 4/8 · злитий образ. Відповідь ремонту (ОБРАЗИ_V1, 5 образів по 4 речі) з поломкою JSON, яку
вирівнювання дужок #331 не лікує: без коми між образами, неекранована лапка в назві, дві коми. Друкує, скільки
образів код узяв, скільки в них речей, чи назвав помилку схеми й чи просить повтор — і що `повнота` віддає на
картку (ід, повний, промпт повноти). Запуск: cd джерела && python3 проби/шлях_виклики_злитий_образ.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), варіантів=10, ремонт_варіантів=5, бюджет_символів=120000, без_фото=1)
пул = json.loads(json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["руки"]["1"])["пул"]
н = lambda с, k: пул[с][k % len(пул[с])]["н"]
образи = [dict(ід="о%d" % (і + 1), підпис="беж", день="Офіс.", речі=[н(с, і) for с in ("верх", "низ", "взуття", "сумка")])
          for і in range(5)]
від = lambda т, **д: json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=т, **д), ensure_ascii=False)))
в1 = від(json.dumps(dict(версія="1", образи=образи), ensure_ascii=False))
ціла = json.dumps(dict(версія="1", образи=образи), ensure_ascii=False)
поломки = {"ціла відповідь": ціла,
           "без коми між о1 і о2": ціла.replace('}, {"ід": "о2"', '} {"ід": "о2"'),
           "лапки в підписі о1": ціла.replace('"підпис": "беж"', '"підпис": "сережки "Pearl" беж"', 1),
           "дві коми між о1 і о2": ціла.replace('}, {"ід": "о2"', '},, {"ід": "о2"'),
           "] замість } (лікує #331)": ціла.replace('}, {"ід": "о2"', '], {"ід": "о2"')}
print("складання: образів %d · ремонт просить %s" % (len(в1["образи"]), (json.loads(в1["промпт_ремонту"])["завдання"] or {}).get("образів")))
for ім, т in поломки.items():
    в2 = від(т, ітерація=2, попередній_вердикт=в1["вердикт"])
    пв = в2.get("повнота") or {}
    print("%-26s → образів %d, речей %s · помилок схеми %d · повтор %s · на картку: ід %d, повний %s, промпт повноти %d симв."
          % (ім, len(в2.get("образи") or []), [len(о.get("ід") or []) for о in в2.get("образи") or []],
             len(в2.get("відповідь_помилки") or []), "так" if в2.get("повторний_виклик") else "ні",
             len(пв.get("ід") or []), пв.get("повний"), len(в2.get("промпт_повноти") or "")))
    if len(пв.get("ід") or []) > 6: print("   жінці: %s" % пв.get("рядок"))
