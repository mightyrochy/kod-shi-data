"""Рядок 2770: де стоїть п'ятий образ ремонту (сміливий `break`/`free` — у 44 з 78) у промпті вибору.
Вхід — записані виклики `choice` розбору 02.10 (`вердикти.txt.gz`: сід запиту, образи о1…о5 у порядку
відповіді ремонту, їхні речі). Перемішування — поточним `порядок_запиту.перемішати_дріт` і колишньою
сіллю «сід|образи». Друкує розподіл позиції о5 і число різних перестановок (0.20 на позицію — рівний шанс).
До правки: одна перестановка на всі 78 виборів, о5 — завжди четвертий.
Прогін: cd джерела && python3 проби/vybir_poriadok_2770.py ../аудит/перевірки/rozbir_0210/*/вердикти.txt.gz"""
import collections, gzip, json, os, random, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import порядок_запиту as ПЗ, протокол as ПР
def виклики(файли):
    for ф in файли:
        try: вв = json.loads(gzip.open(ф, "rt").read())["прогони"][0]["вердикти"]
        except ValueError: print("без вердиктів (не JSON):", ф); continue
        for в in вв:
            for к in (в.get("етапи") or {}).get("виклики", []):
                if к.get("крок") == "choice" and (к["запит"].get("порядок") or {}).get("сід"):
                    о = {x["your_outfit"]["id"]: x["your_outfit"].get("items") or [] for x in json.loads(к["запит"]["текст"])["verdict"]}
                    yield к["запит"]["порядок"]["сід"], [dict(твій_образ=dict(ід=і, речі=о[і.replace("о", "o")])) for і in sorted(к["запит"]["порядок"]["образи"])]
def давній(суд, сід):
    с = list(суд); random.Random("%d|%s" % (сід, ПЗ.сіль("outfits"))).shuffle(с); return с
for назва, f in (("ДО (сід|образи)", давній), ("ПІСЛЯ (сід|образи|склад)",
                 lambda суд, сід: ПЗ.перемішати_дріт({ПР.ВЕРДИКТ_ОБРАЗІВ: суд}, сід, "select", образи=True)[0][ПР.ВЕРДИКТ_ОБРАЗІВ])):
    поз, перест, n = collections.Counter(), set(), 0
    for сід, суд in виклики(sys.argv[1:]):
        ід = [о["твій_образ"]["ід"] for о in f(суд, сід)]
        поз[ід.index("о5") + 1] += 1; перест.add(tuple(ід)); n += 1
    print("%-26s виборів %d · різних перестановок %d · о5 на позиції 1..5: %s" % (
        назва, n, len(перест), " ".join("%.2f" % (поз[і] / max(1, n)) for і in range(1, 6))))
