import json, sys, random, collections as K; sys.path.insert(0, ".")
import bridge as B, стенд_знімок as СЗ, colorspace as cs, колір_річ as КР, колір_відношення as КВ, аксесуари_структура as АС
B.виклик("запити", json.dumps(dict(json.load(open("стенд_вх.json", encoding="utf-8")), сценарій=СЗ.СЦЕНАРІЇ["офіс·18°C"], випадок="офіс"), ensure_ascii=False))
кат = B.каталог_останнього_пакета(); U, Л, А = КВ.ПОХИБКА_ТОНУ, K.Counter(), []
ОД = lambda r: r.get("слот") in ("верх", "сукня", "низ", "верхній_шар")
АК = lambda r: r.get("слот") in АС.СЛОТИ_АКСЕСУАРІВ or r.get("слот") == "взуття"
C = lambda r: cs.lch(tuple(r["lab"]))[1]
def вер(a, b, кл, u):
    КВ.ПОХИБКА_ТОНУ = u
    try: return КР.відношення(a, b, кл)
    finally: КВ.ПОХИБКА_ТОНУ = U
гучні = [r for r in кат if (АС.C_речі(r) or 0) >= 40]
пари = {"А": [(a, b) for a in гучні if ОД(a) for b in гучні if АК(b)]}
кк = [r for r in кат if C(r) >= 12]; оо, аа = [r for r in кк if ОД(r)], [r for r in кк if АК(r)]
р = random.Random(214); пари["Б"] = [(р.choice(оо), р.choice(аа)) for _ in range(100000)]
for п, пп in пари.items():
    for a, b in пп:
        тип = "×".join(sorted("вікно" if КР.не_вимір(x) else "вимір" for x in (a, b)))
        до, піс = вер(a, b, "same_hue", 0.0), вер(a, b, "same_hue", U)
        Л["%s same_hue %-11s %-8s → %s" % (п, тип, до, піс)] += 1
