for ha, hb in (("#e7702f", "#f9842e"), ("#cc6a3b", "#f9842e"), ("#c46a36", "#df9962")):
    a, b = dict(lab=cs.hx(ha)), dict(lab=cs.hx(hb)); print("  2860 %s × %s same_hue %s → %s" % (ha, hb, вер(a, b, "same_hue", 0.0), вер(a, b, "same_hue", U)))
