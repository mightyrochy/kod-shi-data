            дк = КР.кут_на_колі(cs.lch(tuple(a["lab"]))[2], cs.lch(tuple(b["lab"]))[2])
            Л["%s вимір×вимір Δколо %-5s %s → %s" % (п, "≤15" if дк <= 15 else "15–25" if дк <= 25 else "25–45" if дк <= 45 else ">45", до, піс)] += 1
