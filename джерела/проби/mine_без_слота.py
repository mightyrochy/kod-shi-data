# -*- coding: utf-8 -*-
"""Автоогляд Codex на #676 (3): «mine» моделі зору, коли `own_items` у промпті є, але жоден не дав слота
(`мовний_шар._її_речі` порожній: річ без слота й типу, слот поза речами образу, усі — «відмова»).
Порожні `названі` — доказу «річ її» нема, тож «mine» читається «невідомо», як без її речей словами.
Друкує, скільки речей кадру закріплено «твоєю річчю» для кожного набору `own_items`.
Запуск: cd джерела && python3 проби/mine_без_слота.py"""
import json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import річ_з_фото as Р
В = json.dumps({"items": [
    {"photo": "ф1", "name": "yellow shirt", "slot": "top", "color": "yellow", "formality": 5, "owner": "mine"},
    {"photo": "ф1", "name": "yellow pants", "slot": "bottom", "color": "yellow", "formality": 5, "owner": "mine"},
    {"photo": "ф1", "name": "black shoes", "slot": "shoes", "color": "black", "formality": 5, "owner": "mine"}]})
ФОТО = [{"ід": "ф1", "ширина": 600, "висота": 900}]
def річ(**к):
    return dict({"name": {"free_text": "моя річ з фото", "lang": "uk"}, "status": "has", "quote": "моя річ з фото"}, **к)
НАБОРИ = (("без own_items", [], 0),
          ("річ без слота й типу", [річ()], 0),
          ("слот поза речами образу (колготи)", [річ(slot="tights")], 0),
          ("блуза — відмова", [річ(slot="top", status="not_wanted")], 0),
          ("блуза словами (контроль)", [річ(slot="top")], 1))
вада = 0
for підпис, власні, треба in НАБОРИ:
    речі = Р.речі_з_відповіді_фото(В, ФОТО, власні=власні)["речі_з_фото"]
    моя = [р["ід"] for р in речі if р["закріплена"] and р["чия"] == "моя"]
    вада += len(моя) != треба
    print("%-36s → закріплено «твоєю річчю» %d (треба %d): %s" % (підпис, len(моя), треба, ", ".join(моя) or "—"))
print("ВАДА: «mine» без розв'язаного слота закріплює речі кадру" if вада else "OK: без слова зі слотом «mine» не закріплює")
sys.exit(1 if вада else 0)
