"""Друкує названий контекст у вердикті реального образу на повному каталозі."""
import json, pathlib, sys
ДЖ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ДЖ))
import bridge as М, feed as Ф, суд_образу as С


if __name__ == "__main__":
    вхід = json.loads((ДЖ / "стенд_вх.json").read_text(encoding="utf-8"))
    вхід["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
    вхід["гілка"] = 0
    json.loads(М.виклик("запити", json.dumps(вхід, ensure_ascii=False)))
    каталог = М.каталог_останнього_пакета()
    ід = [next(р["id"] for р in каталог if р.get("слот") == слот) for слот in ("сукня", "взуття")]
    відомі = dict(роль="speaker", супутник_рівень=8, сезон="літо", життєвий_перехід="recovery",
                  заявлений_злам=True, тон_колготи=True, заявлена_колона=True)
    номери = {п["вхід"]: п["пункт"] for п in С.чеклісти([], [])["надлишок"] if п["вхід"] in set(відомі) | {"гардероб"}}
    for назва, контекст in (("unknown", dict.fromkeys(відомі)), ("known", відомі),
                             ("negative", dict(відомі, заявлений_злам=False, тон_колготи=False, заявлена_колона=False))):
        в = dict(вхід, ід=ід, сценарій=dict(вхід["сценарій"], **контекст))
        вихід = json.loads(М.виклик("від_моделі", json.dumps(в, ensure_ascii=False)))
        assert "вердикт" in вихід, вихід
        ч = вихід["вердикт"]["образи"][0]["чекліст"]["надлишок"]
        брак = {п["пункт"]: п for п in ч.get("вимкнено", [])}
        assert номери["гардероб"] in брак, ч
        for поле, значення in контекст.items():
            assert (номери[поле] in брак) == (значення is None), (назва, поле, ч)
            if значення is None:
                assert брак[номери[поле]]["бракує"][0]["fields"] == [поле]
        print(назва, "→", ід, "→ без входу:", sorted(поле for поле, номер in номери.items() if номер in брак), flush=True)
