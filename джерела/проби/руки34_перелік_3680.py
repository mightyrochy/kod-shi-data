# -*- coding: utf-8 -*-
"""Рядок 3680 · replay записаних відповідей рук 3–4 (`аудит/живі_*/**/VIDPOVIDI`): проза руки (OUTFIT_TEXT) і її
перелік (ITEM_LIST, пара — за текстом опису в промпті переліку) → `bridge.виклик("від_моделі")`, як кличе показ.
Друкує, скільки карток без речей і на яких відповідях; рядок — з якого шляху речі (перелік чи розбір прози).
ЖИВІ-12 Б/09 рука 4: на коді прогону (`e417eb12`) 0 речей — перелік у {"answer": {…}} не читався; від `f7abb5f4` — 6.
Запуск: cd джерела && python3 проби/руки34_перелік_3680.py [тека, типово ../аудит]"""
import glob, json, os, sys
sys.path.insert(0, "проби"); sys.path.insert(0, ".")
import pal_вердикт as ПВ
def частини(ф):
    т = open(ф, encoding="utf-8").read()
    пр, _, в = т.partition("\n── ВІДПОВІДЬ")
    return пр.partition("──\n")[2].strip(), в.partition("──\n")[2].strip()
вх = ПВ.стенд(гілка=0)[0]
тека = sys.argv[1] if len(sys.argv) > 1 else "../аудит"
проз = sorted(glob.glob(тека + "/живі_*/**/VIDPOVIDI/*проза_рука_3_4*.txt", recursive=True))
порожніх, шлях = [], {}
for ф in проз:
    проза = частини(ф)[1]
    перелік = None
    for ф2 in glob.glob(os.path.dirname(ф) + "/*перелік_речей_руки_3_4*.txt"):
        пр2, в2 = частини(ф2)
        try:
            if json.loads(пр2).get("description") == проза:
                перелік = в2
        except ValueError:
            pass
    d = dict(вх, текст_моделі=проза, **({"перелік_речей": перелік} if перелік else {}))
    в = json.loads(ПВ.B.виклик("від_моделі", json.dumps(d, ensure_ascii=False)))
    в = в.get("вердикт", в)
    к = "перелік" if (в.get("розбір") or {}).get("перелік_моделі") else ("проза" if перелік is None else "перелік не прочитано")
    шлях[к] = шлях.get(к, 0) + 1
    if not (в.get("речі") or []):
        порожніх.append("%s · %s" % (ф.split("живі_", 1)[1][:70], к))
print("пар проза+перелік: %d · речі з: %s · карток без речей: %d" % (len(проз), шлях, len(порожніх)))
for р in порожніх:
    print("  без речей:", р)
