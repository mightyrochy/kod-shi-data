"""Звірити знахідки `верхнє_пропорція` з двох знімків: склад тотожний, ефективна вага — таблиця змін."""
import collections, gzip, json, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
# Літерали без джерела ДО (паспорт, «Крок ваги верхнє_пропорція»): вага ПІСЛЯ — категорія ефективної сили.
ЛІТЕРАЛИ = {'K-OUT-21': 0.7, 'K-OUT-22': 0.4, 'K-OUT-25': 0.2, 'K-OUT-40': 0.2}
# Рішення менеджера 15571: K-OUT-22 заявляє soft — щабель нижче, вхід не встановлює умови правила.
СИЛА = {'K-OUT-22': ('default', 'soft')}


def main():
    """Склад і поля без ваги тотожні; ефективна вага змінилась лише там, де стояв літерал."""
    from реєстр_сила import КАТ_У_НП
    читати = lambda ш: json.load(gzip.open(ш, 'rt', encoding='utf-8'))
    до, після = map(читати, sys.argv[1:3])
    assert len(до) == len(після), (len(до), len(після))
    сирі, еф, всього = collections.Counter(), collections.Counter(), collections.Counter()
    for д, п in zip(до, після):
        сили = СИЛА.get(д[2], (д[3], д[3]))
        assert д[:3] == п[:3] and (д[3], п[3]) == сили and (д[6] == п[6] or д[2] in СИЛА), (д[:4], п[:4])
        всього[д[2]] += 1
        if д[4] != п[4]: сирі[д[2], д[3], д[4], п[4]] += 1
        if д[5] != п[5]:
            еф[д[2], '%s → %s' % (д[3], п[3]) if д[3] != п[3] else д[3], д[5], п[5]] += 1
            assert ЛІТЕРАЛИ.get(д[2]) == д[5] and п[5] == КАТ_У_НП[п[3]], (д[2], д[5], п[5])
    print('знахідок', len(до), 'склад тотожний; сила й поля без ваги — крім', СИЛА, '; сирих змін', sum(сирі.values()),
          'ефективних', sum(еф.values()))
    print('| Правило | Сила | ДО | ПІСЛЯ | Кількість | з усіх |')
    print('|---|---|---|---|---|---|')
    for (правило, сила, було, стало), к in sorted(еф.items(), key=str):
        print('| %s | %s | %s | %s | %d | %d |' % (правило, сила, було, стало, к, всього[правило]))
    без = sorted(set(всього) - {к[0] for к in еф})
    print('без ефективних змін:', {п: всього[п] for п in без})
    print('сирі зміни поза ефективними:', {к: в for к, в in сирі.items() if к[0] not in ЛІТЕРАЛИ})


if __name__ == '__main__':
    main()
