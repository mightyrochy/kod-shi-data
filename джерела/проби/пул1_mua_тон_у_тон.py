# -*- coding: utf-8 -*-
"""Рядок 1978: K-MUA-01 (названа помада) — суд, не пул (п.17). Стенд + губи #ceb599 (нюд):
скільки великих речей пулу лежать ΔE00 < 5 від помади (до правки 0: куля різала їх у фіді),
і що каже суд на живому шляху `від_моделі` про образ із такою річчю — без пояснення і з «свідомо».
Прогін: cd джерела && python3 проби/пул1_mua_тон_у_тон.py"""
import json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed as Ф, bridge as B, colorspace as cs, палітра_запити as ПЗ
ГУБИ = "#ceb599"
вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["сценарій"] = dict(вх["сценарій"], макіяж={"губи": ГУБИ})
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
пак = [p for p in B._КЕШ_ПАКЕТА.values() if p.get("кандидати")][-1]
пул = ((з.get("пакети") or {}).get("1") or {}).get("пул") or {}
зап = пак.get("_запити_у_фід") or []
print("рядків фіду з кулею K-MUA-01: %d із %d" % (sum(1 for q in зап if q.get("не_ближче_за")), len(зап)))
кат = {c["id"]: c for c in пак["_каталог"]}   # рядок пулу моделі id не несе: id — за (назва, hex)
ід = {(к.get("назва"), к.get("hex")): к["id"] for рр in пак["кандидати"].values() for к in рр}
def de(р):   # колір каталогу (lab) — той самий, яким різала куля й судить суд
    lab = (кат.get(ід.get((р.get("назва"), р.get("hex")))) or {}).get("lab")
    return cs.de00(tuple(lab), cs.hx(ГУБИ)) if lab else 99.0
тон = {с: [р for р in пул.get(с) or [] if de(р) < ПЗ.K_MUA_01_ΔE] for с in ПЗ.K_MUA_01_ПЛОЩА}
print("великих речей у пулі: %d, з них ΔE00 < 5 від помади: %d %s" % (
    sum(len(пул.get(с) or []) for с in ПЗ.K_MUA_01_ПЛОЩА), sum(map(len, тон.values())),
    {с: len(v) for с, v in тон.items() if v}))
с0 = next(с for с in ("верх", "низ", "сукня") if тон.get(с))
річ = тон[с0][0]
інші = [] if с0 == "сукня" else [пул[{"верх": "низ", "низ": "верх"}[с0]][0]["н"]]
образ = [річ["н"]] + інші + [пул["взуття"][0]["н"]]
print("образ:", образ, "— тон у тон:", (річ.get("назва") or "")[:40], "ΔE00 %.1f" % de(річ))
for свід in (None, [dict(річ=річ["н"], чому="тон у тон із губами — задум образу")]):
    о = dict(ід="о1", підпис="тон у тон", речі=образ, **({"свідомо": свід} if свід else {}))
    вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=json.dumps(
        dict(версія="1", образи=[о]), ensure_ascii=False)), ensure_ascii=False)))
    k = [z for z in (вм.get("знахідки") or []) if z.get("правило") == "K-MUA-01"]
    print("%-14s K-MUA-01: %d знахідок, регістр %s, свідомий %s, сила_нп %s" % (
        "з «свідомо»" if свід else "без пояснення", len(k), sorted({z.get("регістр") for z in k}),
        sorted({bool(z.get("свідомий")) for z in k}), [z.get("сила_нп") for z in k]))
