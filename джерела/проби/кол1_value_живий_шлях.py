"""КОЛ-1 (рядок 308): що K-COL-01 каже на образах ЖИВОГО шляху — над файлом вердиктів стенда.

Вхід — `ZVIT_OUT` стенда (`аудит/проби/рв6_стенд.js`, сід 3, каталог_повний). Образи — усі
`образи_кроку` рук 1–2 (те, що код перевіряв у кожному виклику). Стан пункту 3 чекліста
(«структура світлоти») — провал / без входу (з `бракує`) / пройдено; гейт площ — чи у виклику
стоїть утримання «площа». Доти, коли гейт закритий, K-COL-01 не запускався, і «пройдено»
було мовчанням; після КОЛ-1 він судить класом слота або каже «без входу».
Запуск: `python3 проби/кол1_value_живий_шлях.py <звіт.txt>`."""
import json, sys, collections

ПУНКТ = "структура світлоти 2–3 кроки, не шум"
d = json.load(open(sys.argv[1], encoding="utf-8"))
стани, бракує, гейт, образів = collections.Counter(), collections.Counter(), collections.Counter(), 0
for п in d["прогони"]:
    for в in п["вердикти"]:
        if str(в.get("рука")) not in ("1", "2"):
            continue
        for к in (в.get("етапи") or {}).get("виклики") or []:
            закрито = any(у.get("правило") == "площа" for у in к.get("утримано") or [])
            for о in к.get("образи_кроку") or []:
                образів += 1
                гейт["закритий" if закрито else "відкритий"] += 1
                н = (о.get("чекліст") or {}).get("надлишок") or {}
                вим = [x for x in н.get("вимкнено") or [] if x.get("що") == ПУНКТ]
                if ПУНКТ in (н.get("провал") or []):
                    стани["провал"] += 1
                elif вим:
                    стани["без входу"] += 1
                    бракує[(вим[0].get("бракує") or "")[:70]] += 1
                else:
                    стани["пройдено"] += 1
print("ФАКТ · образів рук 1–2: %d · гейт площ: %s" % (образів, dict(гейт)))
print("ФАКТ · пункт 3 (K-COL-01): %s" % dict(стани))
for б, н in бракує.most_common(4):
    print("ФАКТ · бракує ×%d: %s" % (н, б))
