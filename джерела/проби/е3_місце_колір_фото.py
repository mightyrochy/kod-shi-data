"""Місце речі з фото доходить до суду з походженням; «без входу» не стає порадою."""
import sys
from unittest.mock import patch
sys.path.insert(0, ".")
import річ_з_фото as Р, оцінка_образу as О

def головна():
    """Зіставляє серіалізацію й суд трьох станів місця."""
    особа = dict(доступно=True, L_шкіри=75, value_gap=15)
    for слово in ("так", "ні", None):
        р = dict(ід="ф1", слот="шарф", вимір=dict(lab=(10, 0, 0)))
        if слово:
            р["місце_стилістки"] = dict(біля_обличчя=слово, слова="на її образі")
        з = Р.запис_каталогу(р)
        assert з.get("місце_стилістки") == р.get("місце_стилістки")
        with patch.object(О._O, "контраст_особи", return_value=особа):
            суд = О._контраст_обличчя({}, {}, [з], "uncontrolled")
        print("оцінка", слово, "→", "без входу" if суд.get("без_входу") else суд.get("пункт"))
        assert bool(суд.get("без_входу")) == (слово is None)
        assert bool(суд.get("пункт")) == (слово == "так")
    р = dict(ід="ф1", слот="сережки", вимір=dict(lab=(60, 0, 0)))
    for зк, очікувано in (([dict(сила="питання", без_входу="місце_речі", чому="невідомо")], False),
                          ([dict(сила="ok")], True)):
        with patch.object(Р._O, "контраст_особи", return_value=особа), patch.object(Р._КС, "біля_обличчя", return_value=зк):
            в = Р.вердикт(р, {}, {}, {})
        коди = [x["code"] for x in в["повідомлення"]["statements"]]
        assert "item_contrast_lower_near_face" not in коди
        print("поради про контраст", очікувано, "→", коди)

if __name__ == "__main__":
    головна()
