"""П-7: яку схему й основу брав код ДОТИ (перша) і яку бере модель ТЕПЕР — на трьох профілях.
ДОТИ: схема — гілка 0 розвилки; основа в пул не йшла (дуги від рис), «(радимо)» на екрані — перша
рекомендована. ТЕПЕР: `вибір_палітри` → промпт → модель → суддя. Модель: MODEL_URL (OpenAI-сумісна,
MODEL — ім'я) наживо, або файл сирих відповідей {профіль: текст} першим аргументом. Токени — cl100k
(tiktoken; токенізатора Claude офлайн нема), без нього — «—». Друкує факт.
Запуск: cd джерела && python3 проби/п7_вибір_палітри.py [відповіді.json]"""
import json, os, sys, urllib.request
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import bridge, вибір_палітри as ВП
try: import tiktoken; ток = lambda т: len(tiktoken.get_encoding("cl100k_base").encode(т))
except ImportError: ток = lambda т: "—"
Т = dict(зріст=168, обхвати={"плечі": 98, "груди": 92, "талія": 74, "стегна": 99})
П = {"світла·низький": dict(шкіра="#deb295", волосся=["#f1dbaa"], очі="#759087", паспорт=dict(подія="вечеря з колегами", нагода="побачення", місце="ресторан_високий", година=19, темп_c=6, мета="лестити", прикраси="золото")),
     "темна·високий": dict(шкіра="#e8c4ad", волосся=["#2b1d16"], очі="#5a3a22", паспорт=dict(подія="співбесіда в банку", нагода="співбесіда", місце="офіс_корпоративний", дрес_код="business_formal", година=10, темп_c=14, мета="приховати", прикраси="срібло")),
     "руда·середній": dict(шкіра="#f0cdb4", волосся=["#8e4a26"], очі="#5f7fa0", паспорт=dict(подія="весілля подруги", нагода="весілля_гість", місце="весілля_вечірнє", година=17, темп_c=24, мета="експресія", прикраси="золото"))}
сирі = json.load(open(sys.argv[1], encoding="utf-8")) if len(sys.argv) > 1 else {}
def модель(промпт):
    if not os.environ.get("MODEL_URL"): return None
    з = urllib.request.Request(os.environ["MODEL_URL"].rstrip("/") + "/chat/completions", json.dumps({"model": os.environ.get("MODEL", ""),
        "temperature": 0, "messages": [{"role": "user", "content": промпт}]}).encode(), {"Content-Type": "application/json"})
    return json.load(urllib.request.urlopen(з, timeout=300))["choices"][0]["message"]["content"]
for ім, п in П.items():
    d = dict(Т, **п); пер = ВП.перелік(d); р1 = json.loads(ВП.вибір_палітри(d))
    радимо = json.loads(bridge.виклик("палітри", json.dumps(d, ensure_ascii=False)))["вибір_кольору"]["база"]
    print("%s · промпт %d симв / %s ток · схем %d, основ %d" % (ім, len(р1["промпт"]), ток(р1["промпт"]), р1["схем"], р1["основ"]))
    print("  ДОТИ  код: схема «%s» (ранг 1) · основа в пулі — нема (дуги від рис), «(радимо)» на екрані — %s" % (пер["схеми"][0]["схема"], радимо))
    відп = сирі.get(ім) or модель(р1["промпт"])
    if відп is None:
        print("  ТЕПЕР модель: — (нема MODEL_URL і файла відповідей)"); continue
    р2 = ВП.прийняти(d, відп); в = р2["вибір"]; о, пр = в["обрала"], в["причини"]
    print("  ТЕПЕР %s: схема «%s» (ранг %d%s) %s · основа %s (ранг %s) %s · гама %s (%s)" % (о["схема"], в["схема"], в["ранг_схеми"],
          ", рідша" if в["схема_рідша"] else "", пр.get("схема") or "", (в["вибір_кольору"] or {}).get("база"), в["основа_ранг"],
          пр.get("основа") or "", в["гама"], о["гама"]))
    for з in р2["знахідки"]: print("  суддя: %s · %s · сила_нп %s · %s" % (з["правило"], з["регістр"], з["сила_нп"], з["суть"]))
    for х in р2["відхилено"] + ([р2["без_моделі"]] if р2["без_моделі"] else []): print("  суддя: " + х)
