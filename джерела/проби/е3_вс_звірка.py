"""Звірити знахідки `верхнє_стан` з двох знімків: склад і сила тотожні, таблиця змін ваги."""
import collections, gzip, json, sys


def main():
    """Таблиця «правило · сила · ДО · ПІСЛЯ · кількість» для ваги після стелі й після придушення."""
    до, після = (json.load(gzip.open(ш, 'rt', encoding='utf-8')) for ш in sys.argv[1:3])
    assert len(до) == len(після), (len(до), len(після))
    сирі, еф, прид = collections.Counter(), collections.Counter(), collections.Counter()
    for д, п in zip(до, після):
        assert д[:5] == п[:5], (д, п)
        for лік, і in ((сирі, 5), (еф, 6), (прид, 7)):
            лік[д[2], д[4], д[і], п[і]] += д[і] != п[і]
    print('знахідок', len(до), '— склад, суть і сила тотожні; змін сирих', sum(сирі.values()),
          'після стелі', sum(еф.values()), 'після придушення', sum(прид.values()))
    for назва, лік in (('після стелі (ефективна)', еф), ('після придушення K-OUT-01', прид)):
        print('\n%s:\n| Правило | Сила | ДО | ПІСЛЯ | Кількість |\n|---|---|---|---|---|' % назва)
        for (пр, сила, було, стало), н in sorted(лік.items(), key=str):
            if н:
                print('| %s | %s | %s | %s | %d |' % (пр, сила, було, стало, н))


if __name__ == '__main__':
    main()
