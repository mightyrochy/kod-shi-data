"""Друкує місце, метал, ворота й заяви картки на тих самих фактах образу; без моделей."""
import inspect, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import траурний_регістр as Т, міст_відповіді as М, місце_речі as Р


def головна():
    """Звірити невідоме, слово стилістки, факт типу й фурнітуру одягу."""
    тр = Т.траур_сцени(dict(нагода="траур", місце="похорон", прикраси="невідомо"))
    речі = [dict(id="обруч", тип="headband", слот="головний_убір", метал="gold"),
            dict(id="сережки", тип="earrings", слот="сережки", метал="gold"),
            dict(id="блуза", тип="блуза", слот="верх", метал="gold",
                 місце_стилістки=dict(біля_обличчя="так", слова="комір під підборіддям"))]
    for р in речі:
        print(р["id"], "місце", Р.бік_межі(р), "метал", Т.стан_металу_біля_обличчя(р),
              "ворота", Т.траурне_відсічення(р, тр))
    основа = dict(id="ш", тип="блуза", слот="верх", блиск=0, блиск_джерело="фото", блиск_крамниці=2)
    for бік in (None, "так", "ні"):
        р = dict(основа)
        if бік:
            р["місце_стилістки"] = dict(біля_обличчя=бік, слова="шарф " + бік)
        картка = dict(випадок=тр)
        print("блуза з розбіжним блиском", бік, "ворота", Т.траурне_відсічення(р, тр),
              "картка", М._нагода_трауру([р], картка)["повідомлення"])
    обруч = dict(речі[0], місце_речі=Р.записати(dict(речі[0], місце_стилістки=dict(біля_обличчя="ні"))))
    запис = dict(випадок=тр)
    арг = ([обруч], запис, {обруч["id"]: речі[0]})
    if len(inspect.signature(М._нагода_трауру).parameters) < 3:
        арг = ([речі[0]], запис)
    print("запис образу + каталог", М._нагода_трауру(*арг)["повідомлення"])


if __name__ == "__main__":
    головна()
