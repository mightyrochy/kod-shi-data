# -*- coding: utf-8 -*-
"""Рядок 1971 (1): ярус 3 доклав річ — суд мусить іти за НОВИМ складом. Стенд (`стенд_вх.json`), сцени офіс/театр × сіди
3, 5, 7. Образ моделі без взуття (верх, низ, сумка, третя річ — по k-й речі пулу); спроби повноти вичерпано (`дібрати=True`), тож
діру закриває код першим взуттям пулу. Першим у пулі ставиться взуття каталогу, яке суддя мосту (`від_моделі` над складом) у цьому
образі НЕ приймає (K-PAL-03, K-SHO-13…). Факт — картки, які `повнота_набору` прийняла (`повний`), а суддя над фінальним
складом не приймає, і час `повнота_набору`. ДО — та сама проба на базі пачки 2."""
import json, sys, os, time
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, повнота_образу as ПО
СЦЕНИ = {"офіс·18": dict(нагода="робота", місце="офіс", година=9, темп_c=18, дрес_код="business_casual"),
         "театр·14": dict(нагода="театр", місце="театр", година=19, темп_c=14, формат="змішано")}
ТРЕТІ = ("прикраси", "пояс", "шарф", "верхній_шар")
карток = прийнято = не_суд = 0; час, взірці = 0.0, []
for назва, сц in СЦЕНИ.items():
    for сід in (3, 5, 7):
        вх = dict(json.load(open("стенд_вх.json")), сценарій=сц, випадок=назва, сід=сід)
        к = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["кандидати"]
        суддя = lambda н: (json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=[list(x) for x in н]),
                                                                        ensure_ascii=False))).get("вердикт") or {}).get("образи") or []
        for kк in range(3):
            база = [к[с][(сід + kк) % len(к[с])]["id"] for с in ("верх", "низ", "сумка", next(т for т in ТРЕТІ if к.get(т)))]
            взуття = [c for c in B.каталог_останнього_пакета() if c.get("слот") == "взуття"][сід + kк::97][:30]
            суди = суддя([база + [r["id"]] for r in взуття])
            чужі = [r for r, о in zip(взуття, суди) if ПО._чому_не_можна(dict(о, структура=dict(ок=True)))][:1]   # гейт, не діра
            for ч in чужі:
                карток += 1
                к2 = dict(к, взуття=[ч] + [r for r in к["взуття"] if r is not ч])
                т0 = time.time()
                п = ПО.повнота_набору(dict(образи=суддя([база])), кандидати=к2, сценарій=сц, дібрати=True, суддя=суддя)
                час += time.time() - т0
                if not п.get("повний"):
                    continue
                прийнято += 1
                чому = ПО._чому_не_можна((суддя([п["ід"]]) or [{}])[0])
                if чому:
                    не_суд += 1
                    взірці.append("%s с%d k%d: на картці %s · суддя: %s" % (назва, сід, kк, "дібране взуття" if ч["id"] in п["ід"] else "інше", чому[:60]))
print("образів без взуття, де перше взуття пулу суддя не приймає: %d · картку прийнято: %d · з них суддя над фінальним складом "
      "НЕ приймає: %d · час повнота_набору: %.1f с" % (карток, прийнято, не_суд, час))
print("\n".join("   " + x for x in взірці[:4]))
