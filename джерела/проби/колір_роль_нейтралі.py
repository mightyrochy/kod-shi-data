# -*- coding: utf-8 -*-
"""КОЛІР-РОЛЬ: нейтраль K-COL-06 — одне визначення, роль за сім'ями модуля `колір_тон` (крок 26, 13891).

Ахроматична, бура й олива — сім'ї цілими; нейві й кремовий — блоки ISCC-NBS (Kelly–Judd 1976, NBS SP 440:
«Navy» — блоки 183, 187, 188, 201; «Cream» — 89) частками тону вузла. Коридорів тону й хроми
(`warm_neutral`, `cool_neutral`, `темне_буре`, `нейві_зона`) у реєстрі нема. Друкує вид і сили; падає, коли
вид розходиться з сім'єю чи блоком джерела. Запуск із джерела/: python3 проби/колір_роль_нейтралі.py
"""
import sys; sys.path.insert(0, ".")
import colorspace as cs, колір_річ as КР, колір_тон as КТ, реєстр_константи as Р

assert not {"warm_neutral", "cool_neutral", "темне_буре", "нейві_зона"} & set(Р.C), "коридор у реєстрі"
# (hex, очікуваний вид за сім'єю чи блоком модуля): None — колір
зразки = [("#000000", "ахроматична"), ("#808080", "ахроматична"), ("#ffffff", "ахроматична"),
          ("#3b2a20", "тепла"), ("#6d3d2e", "тепла"), ("#c19a6b", "тепла"), ("#c3b091", "тепла"),  # бура сім'я
          ("#1f2a44", "холодна"),                                                                   # нейві: блоки ролі
          ("#c8102e", None), ("#b3d9ff", None), ("#1560bd", None), ("#e2725b", None)]
вади = 0
for hx, очік in зразки:
    lab = cs.hx(hx); L, C, h = cs.lch(lab)
    вид, сім = КР.нейтраль(lab), КТ.сім_я_кольору(lab)[0]
    сили = " ".join(f"{к}={в:.2f}" for к, в in КТ.сили_нейтралі(lab).items() if в >= 0.01)
    print(f"{hx} L{L:.0f} C{C:.0f} h{h:.0f}: {вид or 'колір'} (сім'я {сім}; {сили})")
    вади += вид != очік
# поріг кольору — обернене до `нейтраль()`: нижче — нейтраль, трохи вище — колір
for h, L in ((30.0, 40.0), (250.0, 30.0), (250.0, 80.0)):
    п = КР.поріг_кольору(h, L)
    до, за = КР.нейтраль(КР._lab_з_lch(L, п - 0.01, h)), КР.нейтраль(КР._lab_з_lch(L, п + 0.01, h))
    print(f"поріг h{h:.0f} L{L:.0f}: C* {п:.2f} ({до} → {за or 'колір'})")
    вади += до is None or за is not None
print("стеля нейтралей (обвідна ролі):", КР.стеля_нейтралей(), "· вад:", вади)
sys.exit(bool(вади))
