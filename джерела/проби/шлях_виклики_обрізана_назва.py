# -*- coding: utf-8 -*-
"""Розбір шляху 4/8 · обрізана назва й службовий термін у «свідомі». Код складає текст оголошення як
`назва[:40] + " — " + чому` (`розбір_відповідей._свідомі_з_json`), і цей текст іде в промпти вибору й опису.
Друкує: (1) на коді — текст оголошення для речі пулу з найдовшою назвою; (2) скільки разів «оголошений розрив»
стоїть у промпті складання руки 1 (так ші вчиться цього слова); (3) у файлах вердиктів власника 25.09 —
скільки оголошень рук 1–2 несуть назву, обрізану рівно на 40 символах.
Запуск: cd джерела && python3 проби/шлях_виклики_обрізана_назва.py"""
import glob, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), варіантів=10, ремонт_варіантів=5, бюджет_символів=120000, без_фото=1)
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
пул = json.loads(з["руки"]["1"])["пул"]
н = lambda с, k: пул[с][k % len(пул[с])]["н"]
довга = max(пул["верх"], key=lambda r: len(r.get("назва") or ""))
образи = [dict(ід="о%d" % (і + 1), підпис="беж", день="Офіс.", речі=[довга["н"] if (і == 0) else н("верх", і)] + [н(с, і) for с in ("низ", "взуття", "сумка", "пояс")]) for і in range(5)]
образи[0]["свідомо"] = [dict(річ=довга["н"], чому="узято навмисно")]
в = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=json.dumps(dict(версія="1", образи=образи), ensure_ascii=False)), ensure_ascii=False)))
print("назва в пулі (%d симв.): «%s»" % (len(довга["назва"]), довга["назва"]))
print("образ.свідомі о1:         «%s»" % [с.get("текст") for с in в["образи"][0].get("свідомі") or []][0])
print("«оголошений розрив» у промпті складання руки 1: %d раз(и) · «розрив»: %d" % (з["руки"]["1"].count("оголошений розрив"), з["руки"]["1"].count("розрив")))
for ф in sorted(glob.glob("../аудит/тести/власник_2026-09-25/verdykty-*.json")):
    всього = обрізано = 0
    for п in json.load(open(ф, encoding="utf-8"))["прогони"]:
        for вр in п["вердикти"]:
            if вр.get("рука") not in ("1", "2"): continue
            с = [x for x in str(вр.get("свідомі") or "").split("; ") if x]
            всього += len(с); обрізано += sum(len(x.split(" — ")[0]) == 40 for x in с)
    print("%s: оголошень рук 1–2 %d, назва обрізана на 40 симв. — %d" % (os.path.basename(ф), всього, обрізано))
