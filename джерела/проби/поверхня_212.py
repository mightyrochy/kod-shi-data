def читати(шлях, прапор=None):
    """`cv2.imread` через байти: тека `аудит/проби/…` кирилична, а imread на Windows її не бачить (→ None)."""
    import cv2, numpy as np
    if not os.path.exists(шлях):
        return None
    return cv2.imdecode(np.fromfile(шлях, np.uint8), cv2.IMREAD_COLOR if прапор is None else прапор)


def писати(шлях, зобр, параметри=()):
    """`cv2.imwrite` через байти — та сама причина, що в `читати`."""
    import cv2
    cv2.imencode(os.path.splitext(шлях)[1], зобр, list(параметри))[1].tofile(шлях)


def споживачеві(осн, слова, однотонний=False):
    """Колір, який отримує споживач (мірило, рішення менеджера 25.10): вимір, коли він у вікні слова
    крамниці (ПРОДУКТ п.18, `verify.перевірити`) чи річ однотонна з впевненою маскою (п.18: «і поза
    вікном»), інакше — вікно слова; нема ні того, ні того — невідомо.
    Назва — слово крамниці («річ зберігає слово крамниці», п.18).
    Те саме правило для ДО й ПІСЛЯ: [слово, hex виміру або межі інтервалу, звідки]."""
    import verify as V
    from колір_річ import тип_кольору, точка_кольору
    if осн and тип_кольору(осн) != "вимір":
        ім = next((с for с in слова or [] if V.назва_кольору(с)), осн["слово"])
        return [ім, колір_аркуша(осн), осн.get("за_чим") or тип_кольору(осн)]
    if осн and (осн.get("за_чим") or однотонний or not слова or not any(V.назва_кольору(с) for с in слова)
                or any(V.перевірити(точка_кольору(осн), назва=с)["вердикт"] != "відкинуто" for с in слова)):
        ім = next((с for с in слова or [] if V.назва_кольору(с)), осн["слово"])   # річ зберігає слово крамниці
        return [ім, колір_аркуша(осн), осн.get("за_чим") or "вимір"]
    for с in слова or []:
        ім, в, _ = V.вікно_зі_слова(с)
        if ім:
            запис = dict(колір_тип="інтервал", колір_не_вимір=dict(вікно=в, свідок="shop_word"))
            return [ім, колір_аркуша(запис), "вікно слова" + (" (вимір поза вікном)" if осн else "")]
    return ["невідомо", None, "нема слова"]


def після(тека, зап):
    """ПІСЛЯ з тих самих файлів: поверхня придатна → сегменти й основний; ні → колір за словом крамниці."""
    import cv2
    from жнива_колір import виміряти_поверхню, звести_колір, стиснути_поверхню
    к = зап["ключ"]
    bgr = читати(os.path.join(тека, к + ".jpg"))
    м = читати(os.path.join(тека, к + ".маска.png"), cv2.IMREAD_GRAYSCALE)
    if bgr is None or м is None:
        return None
    арр = читати(os.path.join(тека, к + ".atr.png"), cv2.IMREAD_GRAYSCALE)
    п = виміряти_поверхню(bgr, м, арр, джерело=зап.get("маска"))
    осн = звести_колір(п["сегменти"], None, зап.get("слова_крамниці"))[0] if п["придатна"] else None
    return dict(стиснути_поверхню(п), основний=осн and [осн["слово"], колір_аркуша(осн), осн["частка"]],
                тон=[с["тон"] for с in п["сегменти"]][:1], споживачеві=споживачеві(осн, зап.get("слова_крамниці"), п["візерунок"] == "однотонний"))


def шрифт(розмір):
    from PIL import ImageFont
    for ім in ("arial.ttf", "DejaVuSans.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"):
        try:
            return ImageFont.truetype(ім, розмір)
        except OSError:
            pass
    return ImageFont.load_default()


def рядок(тека, зап, п, підпис, Ш):
    """Один рядок аркуша: кадр | маска | ДО | ПІСЛЯ | текст."""
    import cv2, numpy as np
    from PIL import Image, ImageDraw
    полотно = Image.new("RGB", (Ш, ВИСОТА + 10), "white")
    д = ImageDraw.Draw(полотно)
    ф, фм = шрифт(15), шрифт(13)
    x = 5
    bgr = читати(os.path.join(тека, зап["ключ"] + ".jpg"))
    if bgr is not None:
        м = читати(os.path.join(тека, зап["ключ"] + ".маска.png"), cv2.IMREAD_GRAYSCALE)
        накл = bgr.copy()
        if м is not None:
            накл[м > 127] = (0.55 * накл[м > 127] + 0.45 * np.array((255, 0, 255))).astype("uint8")
            конт, _ = cv2.findContours((м > 127).astype("uint8"), cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
            cv2.drawContours(накл, конт, -1, (255, 0, 255), 2)
        for кадр in (bgr, накл):
            h, w = кадр.shape[:2]
            ш = int(w * ВИСОТА / h)
            полотно.paste(Image.fromarray(cv2.cvtColor(cv2.resize(кадр, (ш, ВИСОТА)), cv2.COLOR_BGR2RGB)), (x, 5))
            x += ш + 5
    x = max(x, 2 * ВИСОТА + 15)

    def латки(x, y, заголовок, пари):
        д.text((x, y), заголовок, fill="black", font=ф)
        yy = y + 22
        for сл, колір, ч in пари[:4]:
            if isinstance(колір, dict):
                L0, L1, C0, C1, дуга = колір["межі"]
                тон = "будь-який" if дуга is None else "%g…%g°" % tuple(дуга)
                д.multiline_text((x, yy), "%s · інтервал\nL* %g…%g; C* %g…%g\nh: %s" %
                                 (сл, L0, L1, C0, C1, тон), fill="black", font=фм)
                yy += 58
            else:
                if колір:
                    д.rectangle((x, yy, x + 40, yy + 30), fill=колір, outline="black")
                д.text((x + 46, yy + 6), "%s %s %.0f%%" % (сл, колір or "невідомо", 100 * ч), fill="black", font=фм)
                yy += 34
    до = зап.get("до") or {}
    сп_до = до.get("споживачеві") or ["?", None, ""]
    латки(x, 5, "ДО → %s" % сп_до[0], [(сп_до[2][:22], сп_до[1], 1.0)] +
          [(с, h, ч) for с, ч, h in до.get("кластери") or []][:3])
    x += 230
    if п is None:
        д.text((x, 5), "ПІСЛЯ: нема маски — колір за словом крамниці", fill="black", font=ф)
    else:
        сп = п["споживачеві"]
        латки(x, 5, "ПІСЛЯ → %s · %s" % (сп[0], п["візерунок"] or "невідомо"), [(сп[2][:22], сп[1], 1.0)] +
              [(с, h, ч) for с, ч, h, _ in п["сегменти"]][:3])
        if not п["придатна"]:
            д.multiline_text((x, 150), "\n".join(_розбити(п["чому"], 34)[:4]), fill="black", font=фм)
    x += 260
    д.multiline_text((x, 5), "\n".join(_розбити(підпис, 44)[:12]), fill="black", font=фм)
    return полотно


def _розбити(т, n):
    вих, р = [], ""
    for сл in (т or "").split():
        if len(р) + len(сл) + 1 > n:
            вих.append(р)
            р = сл
        else:
            р = (р + " " + сл).strip()
    return вих + ([р] if р else [])


def аркуш(тека, ім, ключі, записи, пп, підписи):
    from PIL import Image
    Ш = 1500
    рядки = [рядок(тека, записи[к], пп.get(к), підписи.get(к, ""), Ш) for к in ключі if к in записи]
    if not рядки:
        return
    а = Image.new("RGB", (Ш, sum(р.size[1] for р in рядки)), "white")
    y = 0
    for р in рядки:
        а.paste(р, (0, y))
        y += р.size[1]
    а.save(os.path.join(тека, "аркуш_%s.jpg" % ім), "JPEG", quality=85)      # PIL пише юнікодний шлях сам


def main():
    import colorspace as CS
    ап = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ап.add_argument("--тека", default=os.path.join(КОРІНЬ, "аудит", "проби", "поверхня_212"))
    тека = ап.parse_args().тека
    записи = {з["ключ"]: з for з in json.load(open(os.path.join(тека, "вимір.json"), encoding="utf-8"))["записи"]}
    пп = {к: після(тека, з) for к, з in записи.items() if not з.get("помилка")}
    for з in записи.values():           # ДО — тим самим правилом споживача, що й ПІСЛЯ
        до = з.get("до") or {}
        осн = до.get("основний")
        if до:
            до["споживачеві"] = споживачеві(осн and dict(слово=осн[0], hex=осн[1], lab=CS.to_lab(
                tuple(int(осн[1][і:і + 2], 16) for і in (1, 3, 5)))), з.get("слова_крамниці"), not до.get("другий"))
    with open(os.path.join(тека, "після.json"), "w", encoding="utf-8") as ф:
        json.dump(пп, ф, ensure_ascii=False, indent=1)
    вердикти = {"%02d" % в["№"]: в for в in json.load(open(ВЕРДИКТИ, encoding="utf-8"))}
    підписи = {к: "№%s %s · крамниця «%s» · маска %s · очі: %s" % (к, з["id"], ", ".join(з.get("слова_крамниці") or []),
                                                                   з.get("маска"), (вердикти.get(к) or {}).get("що_видно", ""))
               for к, з in записи.items()}
    в_класах = set()
    for ім, номери in КЛАСИ:
        ключі = ["%02d" % н for н in номери]
        в_класах.update(ключі)
        аркуш(тека, ім, ключі, записи, пп, підписи)
    аркуш(тека, "решта", sorted(к for к in записи if к in вердикти and к not in в_класах), записи, пп, підписи)
    аркуш(тека, "8073_cooshwear", sorted(к for к in записи if к.startswith("к")), записи, пп, підписи)
    for к in sorted(записи):
        з, п = записи[к], пп.get(к)
        print(к, ((з.get("до") or {}).get("споживачеві") or [None])[:2], "→", п and п["споживачеві"],
              п and п["візерунок"], п and п["тон"], з.get("помилка") or "")


if __name__ == "__main__":
    main()
