"""Р-1: чужа річ у кадрі її фото більше не стоїть у кожному образі. До / після.

Сира відповідь живого прогону 26.09 (`аудит/тести/сирі_2026-09-26/`): на фото її спідниці,
знятої на моделі, чотири речі — бежевий топ (owner «unknown»), її спідниця («mine»),
срібні човники («unknown») і на другому фото її козаки («mine»). Доти `закріпити`
закріплювало КОЖНУ річ зі слотом: закріплених вийшло три, і на чужий топ код казав жінці
«Цю річ ти обрала сама». Тепер потрібен свідок, що річ її (`річ_з_фото.чи_її`).
Прогін: cd джерела && python3 проби/шлях_речі_чужа_в_кадрі.py
"""
import json, os, re, sys, tarfile
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import річ_з_фото as Р
СИРЕ = os.path.join(os.path.dirname(ТУТ), "аудит/тести/сирі_2026-09-26",
                    "vidpovidi_n1_kontsert_gemma_s3.tar.gz")
with tarfile.open(СИРЕ) as а:
    ім = next(н for н in а.getnames() if "речі_з_фото" in н)
    текст = а.extractfile(ім).read().decode("utf-8")
промпт, відповідь = текст.split("── ВІДПОВІДЬ")[0], текст.split("── ВІДПОВІДЬ")[1].split("──", 1)[1]
фото = [dict(ід=ф["id"], ширина=ф["width"], висота=ф["height"])
        for ф in json.loads(re.search(r'\{"photos".*?\], "codes"', промпт, re.S).group(0)[:-10] + "]}")["photos"]]
print("сире: %s · речей у відповіді %d · фото %s"
      % (ім.split("/")[-1], len(json.loads(відповідь)["items"]), [ф["ід"] for ф in фото]))


def прогін(підпис, названі=None, свідок=True):
    """Шлях продукту: П-1 (`речі_з_відповіді_фото`) → шов шару, який перекладає її речі
    словами в `словами` того самого `речі_з_json` (`паспорт_нагоди.паспорт_з_json`)."""
    цілий = Р.чи_її
    if not свідок:
        Р.чи_її = lambda *а, **к: True          # стара умова: свідка не питали
    речі = Р.речі_з_відповіді_фото(відповідь, фото)["речі_з_фото"]
    if названі:
        речі = Р.речі_з_json([], None, досі=речі,
                             словами=[dict(слот=с, назва="спідницю і чоботи", стан="певна")
                                      for с in названі])
    Р.чи_її = цілий
    закр = [р for р in речі if р.get("закріплена")]
    print("%s → закріплено %d із %d" % (підпис, len(закр), len(речі)))
    for р in речі:
        print("   %-22s %-7s чия=%-9s закріплена=%-5s %s"
              % (р.get("назва"), р.get("слот"), р.get("чия"), р.get("закріплена"),
                 р.get("чому_не_закріплена") or ""))


прогін("ДО  (без свідка, як у прогоні 26.09)", свідок=False)
прогін("ПІСЛЯ (свідок `чи_її`, її слів шар не дав)")
прогін("ПІСЛЯ (її слова назвали низ і взуття)", названі=("низ", "взуття"))
