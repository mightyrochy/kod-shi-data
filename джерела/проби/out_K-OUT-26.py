# -*- coding: utf-8 -*-
"""K-OUT-26 (пояс поверх пуховика — навіть той, якого нема в комплекті).

ДО ПРАВКИ: знахідка йшла у відро `ремонти` й до вердикту не доїжджала. Слот
«пояс» через це не мав причини активуватись не заради себе — єдина в темі-11
операція, що кличе ІНШИЙ слот, не доходила ні до моделі, ні до жінки.
ПІСЛЯ: рядок стоїть у `вердикт.образи[0].знахідки`."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
вх["сценарій"].update(темп_c=-5, опади="ні")
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
к = з["кандидати"]
взяти = lambda сл, ум: next((кат[r["id"]] for r in (к.get(сл) or [])
                             if r["id"] in кат and ум(кат[r["id"]])), None)
без_пояса = lambda c: c.get("тип_верхнього") in ("пуховик", "парка") and not c.get("пояс")
# ── БЕРЕМО З КАТАЛОГУ, А НЕ ЛИШЕ З ПУЛУ (рядок 149, 27.09.2026) ──────────────
# Проба падала `TypeError: 'NoneType' object is not subscriptable`: `пуховик` був None.
# Виміряно на `каталог_повний.xml` при −5 °C: у каталозі 87 пуховиків і парок, 82 з них
# без пояса — але в пулі цього сценарію їх НУЛЬ із 32 (пул дає куртки, жилети, плащі,
# пальта). Тобто правило не зникло; зникла річ, на якій його було видно, і зникла з
# ПУЛУ, а не з каталогу. Судить же код не пул, а ОБРАЗ: `перевірити_від_моделі` бере
# речі з каталогу за id і лише позначає ті, що поза кандидатами. Модель може назвати
# таку річ, жінка може її вдягнути — і правило мусить говорити. Проба тому й бере її
# звідти, звідки її візьме живий шлях, і друкує обидва числа.
_пул = [r["id"] for r in (к.get("верхній_шар") or [])
        if r["id"] in кат and без_пояса(кат[r["id"]])]
_каталог = [c for c in кат.values() if c.get("слот") == "верхній_шар" and без_пояса(c)]
пуховик = кат[_пул[0]] if _пул else (_каталог[0] if _каталог else None)
assert пуховик, "у каталозі нема жодного пуховика/парки без пояса — правилу нема на чому спрацювати"
ід = [r["id"] for r in (пуховик, взяти("сукня", lambda c: True),
                        взяти("взуття", lambda c: True)) if r]
print("пуховик/парка без пояса: у ПУЛІ %d із %d кандидатів · у КАТАЛОЗІ %d"
      % (len(_пул), len(к.get("верхній_шар") or []), len(_каталог)))
print("верхній шар:", пуховик["назва"][:56],
      "· тип", пуховик.get("тип_верхнього"), "· пояс", пуховик.get("пояс"),
      "· з пулу" if _пул else "· З КАТАЛОГУ (у пулі цього сценарію такої речі нема)")
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
зн = ((вм.get("вердикт") or {}).get("образи") or [{}])[0].get("знахідки") or []
р = next((z for z in зн if z.get("правило") == "K-OUT-26"), None)
print("K-OUT-26 у вердикті:", "НЕМА" if not р else
      "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:58]))
print("ремонт кличе інший слот:", str((р or {}).get("ремонт"))[:88])
assert р, "K-OUT-26 не доїхав до вердикту — саме та вада, проти якої проба й стоїть"
assert "пояс" in str(р.get("ремонт") or "").lower(), р
