# -*- coding: utf-8 -*-
"""ФІГУРА-4, рядки 2031/2032: одна мова крою. Каталог руки 1, тіло стенда. Друкує: частку суконь і речей пулу, чиє
слово крою поза кроями слота (ДО: слово ∉ `КРІЙ_СЛОТ[слот]`; ПІСЛЯ: `крої_слота` дає причину «поза слотом»);
скільки речей пулу несуть моделі сире слово, що ≠ кроям слота (`_річ_пулу`); ширину straight-сукні на коліні:
ДО `straight` (штанина), ПІСЛЯ `shift`. Запуск з теки `джерела`: python3 проби/фіг4_мова_крою.py"""
import sys, os, json, collections
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge as B, feed as Ф, outfit as O, силует_запит as СЗ, silhouette as СЛ, fit as ПС, пакет_моделі as П
вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml"); вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = [c for c in B.каталог_останнього_пакета() if c.get("слот") in ("верх", "верхній_шар", "низ", "сукня")]
Z = collections.Counter()
for c in кат:
    к, сл = O._крій_слово(c), c["слот"]
    if not к: continue
    Z[сл, "речей зі словом"] += 1
    Z[сл, "ДО: слово поза слотом"] += not (сл in СЗ.КРІЙ_СЛОТ.get(к, ()) or (сл == "верхній_шар" and "верх" in СЗ.КРІЙ_СЛОТ.get(к, ())))
    Z[сл, "ПІСЛЯ: поза слотом без перекладу"] += O.крої_слота(c)[1] == "cut_word_outside_slot"
    дріт = П._річ_пулу(c, {}).get("крій")
    Z[сл, "ДО: дріт ≠ крої слота"] += к != O.крій_для_моделі(c)       # сире слово проти мови крою слота
    Z[сл, "ПІСЛЯ: дріт ≠ крої слота"] += дріт != O.крій_для_моделі(c)
for k in sorted(Z): print("%-12s %-36s %d" % (*k, Z[k]))
T = ПС.тіло(float(вх["зріст"]), {k: float(v) for k, v in вх["обхвати"].items()})
дай = {nm: w for nm, _, w in T["профіль"]}.get
стр = [c for c in кат if c["слот"] == "сукня" and c.get("тип") != "комбінезон" and c.get("крій") == "straight"]
ш = lambda кр: round(СЛ.ширина_крою(кр, "коліно", дай)[0] / дай("коліно"), 2)   # виріб / тіло на коліні
print("straight-сукні %d: крій у геометрії ДО «straight» (штанина) → ПІСЛЯ «%s»; припуск на коліні ДО %s → ПІСЛЯ %s"
      % (len(стр), O.крій_речі(стр[0]), ш("straight"), ш(O.крій_речі(стр[0]))))
