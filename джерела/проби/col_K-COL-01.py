# -*- coding: utf-8 -*-
"""K-COL-01 (структура світлоти) — ціле, і його утримання на живому вході чесне.

Корпус (тема-4:2477): «2–3 виразні кроки світлоти. Рівна світлота всюди =
площинність (рятується текстурою). Хаотична світлота = шум. Світлоту розвʼязувати
до тону. FORCE: strong, повний штраф, НІКОЛИ не вето (регістр `репліка`)».
ПРАВИЛО ПРАЦЮЄ Й ДІЄ У ТРЬОХ МІСЦЯХ, і проба стверджує всі три:
  1. вердикт — `колір_образу.перевірка_value` над ВИМІРЯНИМИ площами;
  2. утримання — на живому вході площ нема, і правило не вгадує, а називає себе
     у знахідці «площа» (`_утримано_без_площ.утримані_правила`);
  3. пропозиція — крок `step_min` тим самим числом відбирає трійки, які код
     пропонує жінці (`palettes.набір_законний`, K-PAL-15).
Запуск із теки `джерела`: `python3 проби/col_K-COL-01.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import колір_образу as КО, palettes as PAL, реєстр_правил as РЕЄСТР, composer as КМ, outfit as O

крок = РЕЄСТР.C["step_min"]
вх, r, кат, спец = ПВ.стенд(гілка=0)
за_ід = {c["id"]: c for c in ПВ.B.каталог_останнього_пакета()}
# ── ВИМІР, А НЕ СЛОВО КРАМНИЦІ (рядок 149) ────────────────────────────────────
# Доти проба брала перших кандидатів пулу, а вони після рядка 141 (#231) приходять
# із полем `колір_не_вимір`. Вхід виходив суперечливий: площа — «маски», світлота
# приписана рукою (L*60), а колір — центр вікна слова. Правило чесно бачило поле й
# віддавало «питання» замість вердикту — і мало рацію. Пункт 1 стверджує вердикт над
# ВИМІРЯНИМ входом, тож і речі бере виміряні; слово крамниці стверджує пункт 4.
вимір = lambda з: not з.get("колір_не_вимір")
_виміряні = {с: ПВ.з_каталогу(кат, с, lambda L, C, h, з: вимір(з))
             for с in ("верх", "низ", "взуття", "сумка")}
ід = [x["id"] for x in _виміряні.values()]
речі = [КМ._у_річ(dict(за_ід[i]), за_ід[i]["слот"], вх.get("тіло")) for i in ід]
E = O.елементи(речі, "у приміщенні")
print("1) вердикт над ВИМІРЯНИМИ площами (крок корпусу %.0f L*):" % крок)
пласко = [dict(e, L=60.0, площа=п, джерело_площі="маски") for e, п in zip(E, (.45, .30, .10, .15))]
z = next(x for x in КО.перевірка_value(пласко) if x["правило"] == "K-COL-01")
print("   усі речі на L*60 (колір виміряний) → %s %.2f · %s · %s"
      % (z["сила"], z["сила_нп"], z["регістр"], z["суть"]))
print("2) утримання на ЖИВОМУ вході (площі не виміряні):")
у = КО._утримано_без_площ(E)
print("   «%s» · покриття входу %s · утримано: %s"
      % (у["суть"][:52], у["покриття_входу"], "; ".join(КО.ПЛОЩОЗАЛЕЖНІ)[:60]))
print("3) той самий крок відбирає трійки, які код ПРОПОНУЄ:")
поєднань = спец["палітра_практична"]["поєднання"]
близькі = PAL.набір_законний([(50.0, 20.0), (50.0 + крок - 1, 20.0)])
далекі = PAL.набір_законний([(50.0, 20.0), (50.0 + крок + 1, 20.0)])
print("   пара на ΔL* %.0f → %s; на ΔL* %.0f → законна. Трійок у пакеті: %d"
      % (крок - 1, близькі[1], крок + 1, len(поєднань)))
assert z["сила"] == "strong" and z["регістр"] == "репліка", z
assert "K-COL-01 (структура світлоти)" in у["утримані_правила"] and у["покриття_входу"] == 0.0, у
assert близькі[0] is False and далекі[0] is True, (близькі, далекі)   # крок корпусу тримає
assert поєднань, "код не запропонував жодної трійки"

# ── 4) СЛОВО КРАМНИЦІ ЗАМІСТЬ ВИМІРУ: не мовчання, а «без входу» з названим полем ──
# аудит/ПРОДУКТ.md п.4. Той самий синтетичний вхід (площі «маски», всі на L*60), але речі —
# ті, чий колір лише слово. Правило не вгадує однорівневість за побудовою (центр
# вікна однаковий для всіх речей із тим самим словом), а називає поле `колір_не_вимір`.
_словом = {с: ПВ.з_каталогу(кат, с, lambda L, C, h, з: not вимір(з))
           for с in ("верх", "низ", "взуття", "сумка")}
речі4 = [КМ._у_річ(dict(за_ід[x["id"]]), x["слот"], вх.get("тіло")) for x in _словом.values()]
пласко4 = [dict(e, L=60.0, площа=п, джерело_площі="маски")
           for e, п in zip(O.елементи(речі4, "у приміщенні"), (.45, .30, .10, .15))]
z4 = next(x for x in КО.перевірка_value(пласко4) if x["правило"] == "K-COL-01")
print("4) той самий вхід СЛОВОМ крамниці → %s %.2f · %s · без входу: %s"
      % (z4["сила"], z4["сила_нп"], z4["регістр"], z4["без_входу"]))
assert z4["сила"] == "питання" and z4["регістр"] == "питання" and z4["сила_нп"] == 0.0, z4
assert z4["без_входу"] == "колір_не_вимір" and z4["бракує"], z4
