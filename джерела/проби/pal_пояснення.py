# -*- coding: utf-8 -*-
"""ПОЯСНЕННЯ: метал, найдальші, поєднання і прийоми доїжджають до моделі й до опису.

K-PAL-11 (метал), K-PAL-14 (найдальші), K-PAL-15 (поєднання), K-PAL-02…13
(прийоми) рахувались і лишались у `palettes.словами` — тобто в брифі. У ПАКЕТІ
(`ЛЮДИНА.палітра`) стояли лише схема, ролі слотів, нейтралі й акценти; у промпті
ОПИСУ (рука 4, єдиний текст, який жінка читає цілком) не було жодного з них.
ПІСЛЯ: `palettes.для_пакета` — один склад на обидва виклики. Чисел у ньому нема:
промпт від початку забороняє моделі говорити нашою шкалою.
Запуск із теки `джерела`: `python3 проби/pal_пояснення.py`."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import bridge as B, протокол as ПР

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["гілка"] = 0
вх["каталог"] = "каталог_brief.xml"
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
пал = json.loads(r["руки"]["1"])["людина"]["палітра"]
print("ПАКЕТ · ЛЮДИНА.палітра несе: %s" % ", ".join(sorted(пал)))
print("   метал: %s · найдальші: %s" % (пал.get("метал"), пал.get("найдальші")))
print("   поєднань: %d — перше «%s»: %s" % (len(пал.get("поєднання") or []),
      (пал.get("поєднання") or [{}])[0].get("прийом"),
      ", ".join((пал.get("поєднання") or [{}])[0].get("кольори") or [])))
print("   прийомів: %d — %s" % (len(пал.get("прийоми") or []),
      ", ".join(x["прийом"] for x in (пал.get("прийоми") or []))))
assert not (ПР.перевірити(ПР.СХЕМИ["ПАКЕТ_V1"], json.loads(r["руки"]["1"]))), "пакет розійшовся зі схемою"
for к in ("метал", "найдальші", "поєднання", "прийоми"):
    assert пал.get(к), "у пакеті нема «%s»" % к

речі = [x["id"] for пул in r["кандидати"].values() for x in пул][:3]
о = json.loads(B.виклик("опис", json.dumps(dict(вх, речі=речі, образ="о1"), ensure_ascii=False)))
опал = (о.get("опис") or {}).get("палітра") or {}
print("ОПИС · промпт %d символів · палітра в ньому: %s"
      % (len(о["промпт"]), ", ".join(sorted(опал)) or "НЕМА"))
assert not ПР.перевірити(ПР.СХЕМИ["ОПИС_V1"], о["опис"]), "опис розійшовся зі схемою"
for к in ("метал", "найдальші", "поєднання", "прийоми"):
    assert опал.get(к), "в описі нема «%s»" % к
print("ФАКТ · чотири прийоми палітри доїжджають обома каналами; ID корпусу в тексті для "
      "моделі нема: %s" % ("нема" if "K-" not in о["промпт"] else "Є — витік"))
assert "K-COL" not in о["промпт"] and "K-PAL" not in о["промпт"]
