"""Реєстр проблем каталогу, напрям Б, клас Б8: метал, блиск і прозорість — піксель фото не є кольором матеріалу.
Рядки 2440 (камені без входу), 3991 (вікно «золотий» C 15–60, моделі кажуть C 63–87), 5026 (органза: шкіра просвічує).
ФАКТ — записи з металевим словом кольору: чим їх виміряно й що сказало фото; записи з блиском ≥ 2; коду прозорості нема.
Слово «металеве» тут розпізнає проба (міра), не продукт. Запуск: cd джерела && python3 -W ignore проби/каталог_проблеми_б_метал.py"""
import collections, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as FK
К = FK.прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"]
МЕТАЛ = ("золот", "срібл", "срібн", "металік", "gold", "silver")
мет = [r for r in К if any(м in (r.get("колір_назва") or "").lower() for м in МЕТАЛ)]
import колір_річ as _КОЛІР
print("ФАКТ · записів %d; металеве слово кольору %d: з виміром %d, код = центр вікна слова %d; слоти %s" % (
    len(К), len(мет), sum(bool(r.get("колір_hex_фото")) for r in мет), sum(bool(_КОЛІР.провенанс_кольору(r)) for r in мет),
    collections.Counter(r["слот"] for r in мет).most_common(5)))
print("ФАКТ · слово з фото для металевих: %s" % collections.Counter(r.get("колір_назва_фото") for r in мет).most_common(8))
бл = [r for r in К if (r.get("блиск") or 0) >= 2]
print("ФАКТ · блиск ≥ 2 (лак, атлас, метал): %d, з них з виміром %d; поле `метал` у %d записах" % (
    len(бл), sum(bool(r.get("колір_hex_фото")) for r in бл), sum(bool(r.get("метал")) for r in К)))
прозорі = [k for r in К[:1] for k in r if "прозор" in k]
print("ФАКТ · поле прозорості в записі: %s; камені прикрас — окремого входу кольору нема (рядок 2440)" % (прозорі or "нема"))
