# -*- coding: utf-8 -*-
"""Рядок 945: слот розриву вітрини ремонту (`повнота_образу._вітрина_ремонту`, нота «розрив») —
чи падає він біля обличчя (вага `колір_річ.SLOT_NEAR_FALLBACK` ≥ `NEAR_МІН`, поріг K-CLR-02).
(1) вузли напруги образів → слот розриву зараз; (2) живі прогони розбору 02.10: у скількох
`слот_розриву` був біля обличчя (до правки). Моделі не кличе. Запуск: python3 джерела/проби/розрив_обличчя_945.py"""
import glob, gzip, os, re, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ)
import повнота_образу as П, колір_річ as К                                      # noqa: E401,E402
кан = {с: [{"id": "%s%d" % (с, і), "назва": "x", "слот": с} for і in range(3)]
       for с in ("верх", "низ", "пояс", "шарф", "сережки", "взуття", "сумка")}
for вузли in (["пояс", "пояс", "взуття"], ["шарф", "шарф", "низ"], ["сережки", "сережки", "сумка"], ["шарф", "верх"]):
    р = П._вітрина_ремонту([{"ід": ["верх0"], "вузол": в} for в in вузли], кан)[1].get("розрив")
    print("вузли %-28s → розрив %-7s (вага біля обличчя %s, поріг %.2f)" % (
        вузли, р, К.SLOT_NEAR_FALLBACK.get(р) if р else "—", К.NEAR_МІН))
біля, усього = [], 0
for ф in sorted(glob.glob(os.path.join(ТУТ, "..", "аудит", "перевірки", "rozbir_0210", "ж*", "вердикти.txt.gz"))):
    try:
        т = gzip.open(ф).read().decode()
    except (OSError, EOFError) as e:
        print("пропущено %s: %s" % (os.path.basename(os.path.dirname(ф)), e)); continue
    слоти = set(re.findall(r'слот_розриву\\?"?:\\?"([^"\\]+)', т))
    усього += bool(слоти)
    б = sorted(с for с in слоти if К.SLOT_NEAR_FALLBACK.get(с, 1.0) >= К.NEAR_МІН)
    if б:
        біля.append("%s:%s" % (os.path.basename(os.path.dirname(ф)), "+".join(б)))
print("живі прогони 02.10: зі слотом розриву %d, біля обличчя %d · %s" % (усього, len(біля), ", ".join(біля)))
