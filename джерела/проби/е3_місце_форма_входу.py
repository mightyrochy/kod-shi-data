# -*- coding: utf-8 -*-
"""Е3-місце-речі, рішення на КОЛО #3352: читач запису `місце_речі.бік_межі` бере те, що має викликач, — елемент
образу (`outfit.елементи`), річ без запису (запише сам) чи сам запис (`місце_речі.записати`) — і дає однакову
відповідь; інша форма (рядок слота, None, словник без ключів речі, обгортка з не-записом, запис з чужим джерелом) —
виняток `ФормаВходу`. Друкує бік межі трьох форм для взуття, сумки, сережок, окулярів і верху (замір 0811-10:
False, False, True, True, None) і клас винятку для кожної хибної форми. Код 1 — форми розійшлись чи хибна форма дала відповідь.
Запуск: cd джерела && python3 проби/е3_місце_форма_входу.py"""
import os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import outfit, місце_речі as МР
СЛОТИ = ("взуття", "сумка", "сережки", "окуляри", "верх")
речі = [dict(id="р%d" % і, слот=с, hex="#3a3a3a", площа=0.1) for і, с in enumerate(СЛОТИ)]
елементи = {е["річ"]: е for е in outfit.елементи(речі)}
вада, відповіді = 0, []
for р in речі:
    форми = (елементи[р["id"]], dict(р), МР.записати(р))
    боки = [МР.бік_межі(ф) for ф in форми]
    відомі = [МР.біля_обличчя_відоме(ф) for ф in форми]
    відповіді.append(боки[0])
    однакові = len(set(боки)) == 1 and len(set(відомі)) == 1
    вада += not однакові
    print("ФАКТ · %-8s елемент/річ/запис: бік %s; частка %s%s"
          % (р["слот"], боки, відомі, "" if однакові else "  ✗ розійшлись"))
print("ФАКТ · бік межі за слотами %s: %s (замір 0811-10: [False, False, True, True, None])" % (list(СЛОТИ), відповіді))
вада += відповіді != [False, False, True, True, None]
хибні = (("рядок слота", "сережки"), ("None", None), ("список", [речі[2]]), ("порожній словник", {}),
         ("словник без ключів речі", {"колір": "чорний"}), ("обгортка з не-записом", {"місце_речі": "сережки"}),
         ("запис з чужим джерелом", dict(МР.записати(речі[2]), джерело="клас слота")))
for назва, ф in хибні:
    for читач in (МР.бік_межі, МР.біля_обличчя_відоме):
        try:
            відповідь = читач(ф)
        except МР.ФормаВходу as e:
            print("ФАКТ · %-24s %s → ФормаВходу: %s" % (назва, читач.__name__, e))
            continue
        вада += 1
        print("ФАКТ · %-24s %s → %r  ✗ хибна форма дала відповідь" % (назва, читач.__name__, відповідь))
print("ПІДСУМОК · вад %d" % вада)
sys.exit(1 if вада else 0)
