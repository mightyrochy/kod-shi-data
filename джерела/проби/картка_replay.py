"""Replay записаних VIDPOVIDI: факт виміру, без моделі й мережі."""
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'прилади'))
from replay_картки import виміряти


def main():
    """Надрукувати всі числа й перевірити межі на незмінному корпусі."""
    шлях = Path(__file__).parent / 'дані' / 'картка_запиту.json'
    л = виміряти(шлях)['лічба']
    print(json.dumps(л, ensure_ascii=False))
    нулі = ('her_без_уривка', 'година_без_числа', 'втрачено_годин', 'нагода_стерта',
            'службові_recorded', 'числа_recorded', 'типове_chosen',
            'без_підтвердження', 'обрубків_до_показу', 'стерта_цитата',
            'змінена_пора', 'масив_нагод_втрачено', 'пора_без_уривка')
    assert all(л[к] == 0 for к in нулі), {к: л[к] for к in нулі if л[к]}
    assert л['ходів'] == 53 and л['реплік'] == 16 and л['плиток'] == 8
    assert л['J_відмов'] == л['J_поганих'] and л['J_хибних'] <= 1
    print('Покриття: 53/58 ходів; 9/13 поточного контракту; 3/5 названих годин; '
          '23/27 власних реплік; 6/8 добрих реплік. Решта: гілки 3.2-Е/Г недоступні локально.')


if __name__ == '__main__':
    main()
