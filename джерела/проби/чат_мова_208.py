"""Рядок 208 · Т-4/Т-6: що жінка читає в чаті, коли модель (qwen3.5-9b, 24.09) пише
російськими словами або називає врахованим те, що код відкинув. Фрази — дослівні зі звіту
тестувальниці; решта відповіді відтворена. Друкує текст чату, як його складає показ.
Та сама проба на дереві main дає «до». Запуск: cd джерела && python3 проби/чат_мова_208.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B
сц = {"нагода": "робота", "місце": "офіс", "дрес_код": "business_casual"}
чат = lambda п: " | ".join(x for x in [п.get("відповідь_людині"), п.get("порада_людині")]
                           + list(п.get("питання_людині") or []) if x)
def паспорт(ім, слова, об, перепис=()):
    р = json.loads(B.виклик("паспорт", json.dumps(dict(сценарій=сц, вимоги=слова, json_моделі=json.dumps(
        dict(об, джерело="модель"), ensure_ascii=False)), ensure_ascii=False)))
    print("── %s\n   чат: %s\n   повтор мови: %s · знято з чату: %s" % (ім, чат(р["паспорт"]),
          "так" if р.get("повтор_мови") else "ні", [з["знято"] for з in р["паспорт"].get("чат_узгоджено") or []] or "—"))
    for с, т in enumerate(перепис, 1):
        if not р.get("повтор_мови"):
            break
        р = json.loads(B.виклик("паспорт", json.dumps(dict(перепис_чату=т, паспорт_розбір=р["паспорт"], спроба=с),
                                                      ensure_ascii=False)))
        м = р["паспорт"].get("мова_чату") or {}
        print("   перепис %d → чат: %s · %s" % (с, чат(р["паспорт"]), м.get("стало") or м.get("позначка") or "—"))
паспорт("Т-6 · «романтичний» з прикладу промпта", "робочий день в офісі, дрес-код business casual, без підборів",
        dict(нагода="робота", реєстр_людини=["романтичний"],
             відповідь_людині="Зрозуміла: робочий день в офісі, враховуючи твій романтичний стиль (по-дівчачому)."))
рос = "Під світлых джинсів візьми куртку-ветровку поверх светру."
паспорт("Т-4 · російські слова, перепис чистий", "гуляю з собаками в парку, вітер, світлі джинси",
        dict(нагода="прогулянка", відповідь_людині=рос),
        перепис=['{"відповідь_людині": "Під світлі джинси візьми вітрівку поверх светра."}'])
паспорт("Т-4 · перепис двічі з російською → Р-2", "гуляю з собаками в парку, вітер, світлі джинси",
        dict(нагода="прогулянка", відповідь_людині=рос),
        перепис=['{"відповідь_людині": "%s"}' % рос] * 2)
паспорт("Т-6 · числа дня, яких вона не казала", "іду в офіс на цілий день",
        dict(нагода="робота", темп_c=18, година=11, відповідь_людині="Зрозуміла: офіс, о 11:00, +18 °C — легкий верх."))
