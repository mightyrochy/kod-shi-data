# -*- coding: utf-8 -*-
"""Рядок 110: чи несе `graph.зона` формальність речі — і чим це коштує пакету.

ДО (main, хвиля 103): ключ `формальність` не з'являвся у вузлі ЖОДНОГО разу
(`tuple(int)` кидав TypeError, який ковтав `except`), тож рядок формальності не
доїжджав до моделі. ПІСЛЯ: інтервал будує `формальність.інтервал_формальності`
(шкала 1–10 — та сама, що `ошатність` сценарію), `формальність_чому` лишається
лише там, де тип рівня не має. Рядок речі несе числа («форм. 3–6»), а шкалу
пакет оголошує один раз у брифі (`пакет_моделі.ВИМОГИ_ПАКЕТА`) — 20.09.2026.
Запуск: PYTHONPATH=. python3 проби/formalnist_110.py
"""
import json, collections
import bridge as B, graph as G

вх = json.load(open("стенд_вх.json"))
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
є = collections.Counter(); всього = collections.Counter(); чому = collections.Counter()
for x in кат:
    з, с = G.зона(x), (x.get("слот") or "без_слота")
    всього[с] += 1
    if "формальність" in з: є[с] += 1
    if "формальність_чому" in з:
        т = з["формальність_чому"]
        чому[т.split("«")[-1].split("»")[0] if "«" in т else "типу нема"] += 1
print("каталог %d · формальність у вузлі %d (%.1f %%) · формальність_чому %d"
      % (len(кат), sum(є.values()), 100.0 * sum(є.values()) / len(кат), sum(чому.values())))
print("по слотах:", ", ".join("%s %d/%d" % (с, є[с], всього[с])
                              for с in sorted(всього, key=lambda k: -всього[k])[:10]))
print("без рівня (топ):", ", ".join("%s %d" % t for t in чому.most_common(6)))

пак = json.loads(r["руки"]["1"])
зони = [x["зона"] for v in пак["пул"].values() for x in v if x.get("зона")]
зф = [z for z in зони if "форм. " in z]
print("пул руки 1 %d речей · пакет %d символів · рядків з формальністю %d з %d"
      % (sum(len(v) for v in пак["пул"].values()), len(r["руки"]["1"]), len(зф), len(зони)))
print("приклад рядка:", зф[0] if зф else "— формальності в пакеті НЕМА (стан main)")
import пакет_моделі as ПМ
print("шкала в брифі:", next((в for в in ПМ.ВИМОГИ_ПАКЕТА if "шкалою 1–10" in в), "— НЕ оголошена"))
