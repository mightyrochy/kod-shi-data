"""Звірка знімків `виконання/е3_присвоєння.py` ДО і ПІСЛЯ: склад, сира й ефективна вага, позначка підлоги."""
import collections, gzip, json, sys


def читати(шлях):
    """Записи знімка за ідентичністю знахідки (без ваги); провали обгортки."""
    with gzip.open(шлях, 'rt', encoding='utf-8') as ф:
        д = json.load(ф)
    за = collections.defaultdict(list)
    for р in д['записи']:
        за[tuple(р[:7])].append(tuple(р[7:]))
    return за, д['провали'], len(д['записи'])


def main():
    """Друк: склад, сирі зміни, таблиця ефективних змін «правило · ДО · ПІСЛЯ · кількість»."""
    (до, пд, нд), (після, пп, нп) = map(читати, sys.argv[1:3])
    print('записів', нд, '→', нп, '; провали ДО', пд, 'ПІСЛЯ', пп)
    склад = sorted(set(до) ^ set(після))
    print('ключів лише з одного боку:', len(склад), склад[:5])
    сирі, еф, підлога = collections.Counter(), collections.Counter(), collections.Counter()
    for к in set(до) & set(після):
        if len(до[к]) != len(після[к]):
            print('кратність', к[:3], len(до[к]), len(після[к]))
        for (сд, ед, фд), (сп, еп, фп) in zip(sorted(до[к], key=str), sorted(після[к], key=str)):
            if сд != сп: сирі[к[1], к[2], сд, сп] += 1
            if ед != еп: еф[к[1], к[2], ед, еп] += 1
            if фд != фп: підлога[к[1], к[2], фд, фп] += 1
    print('сирих змін', sum(сирі.values()), 'ефективних', sum(еф.values()), 'позначки підлоги', sum(підлога.values()))
    for назва, т in (('СИРІ', сирі), ('ЕФЕКТИВНІ', еф), ('ПІДЛОГА', підлога)):
        print('##', назва, '\n| функція | правило | ДО | ПІСЛЯ | кількість |\n|---|---|---|---|---|')
        for (ф, п, а, б), н in sorted(т.items(), key=str)[:200]:
            print('| %s | %s | %s | %s | %d |' % (ф, п, а, б, н))


if __name__ == '__main__':
    main()
