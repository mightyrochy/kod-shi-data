"""Договір частини дня від відповіді моделі до паспорта й дроту."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import мовний_шар as М, паспорт_нагоди as П, дріт_моделі as Д

assert "пора" in П.СХЕМА_ПАСПОРТА and "година" not in П.СХЕМА_ПАСПОРТА
for код, слово in (("morning", "ранок"), ("day", "день"), ("evening", "вечір"), ("night", "ніч")):
    р = М.прийняти_розмову(json.dumps({"update": {"part_of_day": код}}))
    п = М.паспорт_з_шару(р["внутрішня"], {}, паспорт_досі={"година": 19, "хвилини": 30},
                         частини=р.get("частини"))["паспорт"]
    assert п.get("пора") == слово and "година" not in п and "хвилини" not in п
    дріт = Д.випадок(п)
    assert дріт["part_of_day"] == код and "start_hour" not in дріт
р = М.прийняти_розмову(json.dumps({"update": {"part_of_day": "unknown"}}))
п = М.паспорт_з_шару(р["внутрішня"], {})["паспорт"]
assert not п.get("пора")
print("Чотири частини дня й невідоме: паспорт і дріт без години — пройдено")
