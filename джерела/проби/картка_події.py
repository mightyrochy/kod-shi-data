"""Факти мосту: явний дотик без дифу, новіша розмова, читачі картки."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import мовний_шар as м
import картка_запиту as к


def main():
    """Виміряти порядок дотик → слова → плитки без моделі й мережі."""
    сц = dict(година=11, темп_c=18, типові_поля=['година', 'темп_c'])
    assert м.плитки_кодами(сц) == {}
    сц['події_руки'] = [dict(поле='година', значення=11, джерело='hand')]
    п = м.паспорт_з_шару({}, сц, лише_плитки=True)['паспорт']
    assert к.факт(п, 'година')['джерело'] == 'hand'
    assert м.плитки_кодами({}, п) == {'hour': 11}
    вн = dict(hour=19, quotes=dict(hour='о 19:00'))
    п = м.паспорт_з_шару(вн, сц, паспорт_досі=п, слова_ходу='о 19:00')['паспорт']
    assert п['година'] == 19 and к.факт(п, 'година')['джерело'] == 'her'
    п = м.паспорт_з_шару(dict(hour=11), {}, паспорт_досі=п, лише_плитки=True)['паспорт']
    assert п['година'] == 19
    запис = м.записано_для_репліки(dict(hour=11, occasion_part='other'), п)
    assert запис == {'hour': dict(label='19:00', quote='о 19:00', source='her')}
    assert п['звідки']['hour'] == 'her_words'
    к.дотики(п, [dict(поле='година', значення=None, джерело='hand')])
    assert not м.плитки_кодами({}, п)
    print('Типове у chosen: 0; дотик без дифу: hand; новіша розмова: her; слабший повтор: збережено; очищення: hand.')


if __name__ == '__main__':
    main()
