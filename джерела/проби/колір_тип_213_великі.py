"""Однакові сім'ї інтервалу в каталозі, пулі, площах і словах образу."""
import sys
sys.path.insert(0, ".")
import палітра_схеми as П, verify as В, фід_збагачення as З, areas as А


def головна():
    """Порахувати червоний інтервал і запропонувати наявну заміну нейтралі."""
    р = dict(id="слово-червоний", слот="верх", колір_назва="червоний", lab=None,
             колір_тип="інтервал", колір_не_вимір=З.не_вимір_кольору(
                 В.ЛЕКСИКОН["червоний"], "червоний", "shop_word"))
    с = dict(роль="акцент", дуга=(300, 60))
    індекс, пул = {р["id"]: р}, {"верх": [dict(id=р["id"])]}
    каталог = П._великі_у_каталозі(с, індекс)
    добір = П._великі_у_пулі(с, пул, індекс)
    тіло = dict(профіль=А.профіль_тіла(164, dict(плечі=112, груди=94, талія=74, стегна=100)))
    площі = П.площі_схеми([dict(id=р["id"], слот="верх", верх_см=125, низ_см=85)], [с], тіло, індекс)
    слова = П.слова_у_речах([р["id"]], с, індекс)
    нейтраль = dict(id="білий", слот="верх", lab=(90, 0, 0))
    знахідки = П.обіцянка_великих([нейтраль], {"_сім_ї": [с]}, індекс, пул)
    ремонт = [д["values"]["action"] for з in знахідки for д in з.get("ремонт_заяви", [])]
    print("Каталог:", каталог, "пул:", добір, "слова:", слова,
          "площа:", round(площі["сім_ї"]["акцент"]["площа"], 2), "ремонт:", ремонт)
    assert П.сім_я_схеми(р, [с]) == "акцент" and каталог == 1 and добір == {"верх": 1}
    assert слова == ["червоний"] and площі["сім_ї"]["акцент"]["слоти"] == ["верх"]
    assert площі["невиміряні"] == 0 and знахідки
    assert площі["сім_ї"]["акцент"]["площа"] > 0 and площі["сім_ї"]["акцент"]["частка"] == 1
    assert ремонт == ["replace"] and all("брак асортименту" not in str(з) for з in знахідки)
    for інша in (dict(р, колір_тип="невідомо"), dict(р, колір_не_вимір=dict(
            свідок="shop_word", вікно=(20, 80, 0, 100, None)))):
        assert not П.сім_я_схеми(інша, [с])


if __name__ == "__main__":
    головна()
