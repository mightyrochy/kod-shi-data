# -*- coding: utf-8 -*-
"""РЯДОК 199: взуття бере участь у судженні СТИЛЮ образу, а не тільки формальності.
Вердикти «Ір»: рука 1 — «Взуття надто спортивне для цього образу», рука 2 — «сукня
занадто легка й романтична… балетки чи мокасини не личать». Формальність (K-KOH-02 /
K-SHO-03) міряє, НАСКІЛЬКИ одягнена людина, реєстр (K-REG-01/05/06) — ЯКОЮ МОВОЮ; це
K-REG-00. На main реєстр не бачив 67 % пар каталогу: рядок «Взуття:» теми-13 називає
взуття кожного реєстру поіменно, а в словнику цих слів не було. У її образі балетки
не мали реєстру зовсім — вектор образу збирався із сукні й сумки, і взуття, про яке
вона писала, для цього шару не існувало. Проба рахує пари без реєстру по типах.
Запуск: cd джерела && python3 проби/vzuttia_reiestr_199.py [тека_джерел]  (ДО — те саме на main)"""
import json, os, sys, collections
Д = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, Д); os.chdir(Д)
import feed as Ф, bridge as B, реєстри as РЕ
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
вз = [r for r in кат if r.get("слот") == "взуття"]
без = [r for r in вз if not РЕ.реєстр_речі(r)["розпізнано"]]
усе, нема = collections.Counter(str(r.get("тип")) for r in вз), collections.Counter(str(r.get("тип")) for r in без)
print("ФАКТ · взуття %d · без реєстру %d (%.0f %%) · усього речей %d, без реєстру %d (%.0f %%)"
      % (len(вз), len(без), 100.0 * len(без) / len(вз), len(кат),
         sum(1 for r in кат if not РЕ.реєстр_речі(r)["розпізнано"]),
         100.0 * sum(1 for r in кат if not РЕ.реєстр_речі(r)["розпізнано"]) / len(кат)))
print("   без реєстру по типах (від найбільшого типу): %s"
      % ", ".join("%s %d/%d" % (т, нема.get(т, 0), n) for т, n in усе.most_common(10)))
# її пара з руки 2 і пара, яку тема-13 називає в тому самому рядку іншого реєстру
for тип, чий in (("балетки", "романтичний"), ("сандалі", "бохо"), ("кросівки", "стритвер")):
    рч = [r for r in вз if r.get("тип") == тип]
    хто = collections.Counter(max(РЕ.реєстр_речі(r)["бали"], key=РЕ.реєстр_речі(r)["бали"].get)
                              for r in рч if РЕ.реєстр_речі(r)["розпізнано"])
    print("   «%s» (%d пар): реєстр у %d, найчастіший %s — тема-13 «Взуття:» дає «%s»"
          % (тип, len(рч), sum(хто.values()), хто.most_common(1) or "—", чий))
    assert хто.most_common(1) and хто.most_common(1)[0][0] == чий, "«%s» не читається як %s" % (тип, чий)
assert нема.get("балетки", 0) == 0, "балетки досі без реєстру — вектор образу їх не бачить"
assert 100.0 * len(без) / len(вз) < 60.0, "взуття без реєстру більше за 60 % — шар стилю сліпий"
