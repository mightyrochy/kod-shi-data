# -*- coding: utf-8 -*-
"""Артикул у назві речі: скільки назв каталогу його несли до чистки і скільки після.

Друкує ФАКТ на СИРОМУ каталозі (`каталог_повний.xml.gz` у корені репозиторію):
лічбу до/після і 10 прикладів «до → після». Сирий, а не той, що на диску: файл
на диску чистка вже пройшла (`feed.каталог_на_диску`), і «до» там уже нема.
Артикул — службовий код крамниці («000399639», «1-22480-42», «(2221bg)»,
«D10142020»); розмір, колір і бренд правило не чіпає (`назва_речі.зняти_артикул`).
"""
import gzip, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import назва_речі

ТИПОВИЙ = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       os.pardir, "каталог_повний.xml.gz")
ШЛЯХ = sys.argv[1] if len(sys.argv) > 1 else ТИПОВИЙ
відкрити = gzip.open if ШЛЯХ.endswith(".gz") else open
сирий = відкрити(ШЛЯХ, "rt", encoding="utf-8").read()

# Назва КРАМНИЦІ теж лежить у <name>, але поза <offer> — чистка її не чіпає.
назви = [м.group(1) for о in re.finditer(r"<offer\b.*?</offer>", сирий, re.S)
         for м in re.finditer(r"<name>([^<]*)</name>", о.group(0))]
пари = [(н, назва_речі.зняти_артикул(н)) for н in назви]
з_кодом = [(а, б) for а, б in пари if а != б]
лишилось = [б for _, б in пари if б != назва_речі.зняти_артикул(б)]

print("назв у каталозі: %d" % len(назви))
print("мали артикул ДО правки: %d (%.1f %%)" % (len(з_кодом), 100.0 * len(з_кодом) / len(назви)))
print("мають артикул ПІСЛЯ правки: %d" % len(лишилось))
print("\n10 прикладів «до → після»:")
for а, б in з_кодом[:10]:
    print("  %s\n    → %s" % (а, б))
