# -*- coding: utf-8 -*-
"""Н-7: правило, спростоване експериментом класу A, лишається поясненням, а не вагою.

K-SIL-02 («поділ 1:2/2:1 замість 1:1») стоїть на золотому перетині, який McManus 1980
і Boselie 1992 виміряли як такий, що популяційної привабливості НЕ має. Доти знахідка
виходила регістром «репліка» вагою 0.50 і доїжджала у вердикт нарівні з виміряними
правилами. Після Н-7 вона й далі народжується (пояснення лишається), але важить нуль
і несе поле `спростовано` — а `вердикт_моделі.знахідки_вердикту` нульові відкидає.
Запуск із теки `джерела`: `python3 проби/н7_спростовано.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import fit as ПС, areas as ОБЛ, реєстр_політика as РП, вердикт_моделі as ВМ

проф = ОБЛ.профіль_тіла(168, dict(плечі=98, груди=92, талія=72, стегна=100))
H = {nm: y for nm, y, _ in проф}
тіло = ПС.тіло(168, dict(плечі=98, груди=92, талія=72, стегна=100,
                         коліно=35.0, литка=36.0, щиколотка=22.0))
речі = [dict(id="кардиган", слот="верхній_шар", hex="#4a4438", верх_см=H["плечі"],
             низ_см=round(H["плечі"] / 2, 1), край_джерело="фід", тип="кардиган"),
        dict(id="штани", слот="низ", hex="#3a3a42", верх_см=H["талія"], низ_см=H["щиколотка"],
             край_джерело="фід", тип="штани"),
        dict(id="лофери", слот="взуття", hex="#a9825c", верх_см=3.0, низ_см=0.0,
             край_джерело="фід", тип="лофери")]
зн = ПС.поділ_образу(тіло, речі)
assert зн, "K-SIL-02 не спрацював — проба міряла б порожнечу"
z = зн[0]
рядки, _ = ВМ.знахідки_вердикту([dict(x) for x in зн], речі)
print("ФАКТ · K-SIL-02: сила «%s», регістр «%s», вага %.2f" % (z["сила"], z["регістр"], z["сила_нп"] or 0.0))
print("ФАКТ · поле «спростовано»: %s…" % str(z.get("спростовано"))[:72])
print("ФАКТ · знахідка лишилась поясненням: суть є (%d символів), у вердикті рядків K-SIL-02 — %d"
      % (len(z["суть"]), sum(1 for r in рядки if r["правило"] == "K-SIL-02")))
print("ФАКТ · у таблиці спростувань: %s" % ", ".join(sorted(РП.СПРОСТОВАНО_ЕКСПЕРИМЕНТОМ)))
assert (z["сила_нп"] or 0.0) == 0.0 and z.get("спростовано"), z
assert not [r for r in рядки if r["правило"] == "K-SIL-02"], "спростоване правило доїхало у вердикт"
