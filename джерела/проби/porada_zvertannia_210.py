"""З-3, З-4, З-5в (рядок 210): форму поради, звертання й рід тримає КОД, не промпт.
Жива локальна модель (`qwen/qwen3.5-9b`, сід 7, знімок `z3_z4_porada_pytanniam_vy_seed7.jpg`)
прислала пораду двома питаннями, перейшла на «ви» й сказала про себе «Я підібрав».
ДО — `паспорт_нагоди` з origin/main, ПІСЛЯ — робоче дерево; ті самі рядки моделі
(з `аудит/тести/2026-09-24_прохід_1.md`; сирих `vidpovidi/` у git нема). Два виходи:
поле чату і проза картки. Запуск із `джерела`: PYTHONPATH=. python3 проби/porada_zvertannia_210.py"""
import json, re, subprocess, sys, types; sys.path.insert(0, ".")
import паспорт_нагоди as ПІСЛЯ, розбір_відповідей as РВ
ДО = types.ModuleType("пн_до"); ДО.__dict__["__name__"] = "пн_до"
exec(subprocess.run(["git", "show", "origin/main:джерела/паспорт_нагоди.py"],
                    capture_output=True, text=True).stdout, ДО.__dict__)
ТЕМИ, РЯДКИ = ["мета", "макіяж", "прикраси"], [
    "Оскільки це ранковий діловий час у офісі, я б підбрала зручну тканину для повільного "
    "руху: чи ви обранете класичні брюки/спідницю, чи жодної прикраси не хочете?",
    "Я підібрав охайні буденні образи — сьогодні у вас робочий день в офісі.",
    "Я зрозуміла: сьогодні у вас робочий день в офісі.",
    "Якщо хочеш, підкажи, чи хочеш сьогодні бути помітною, чи буде яскрава помада і які "
    "прикраси любиш з таким образом — а можна й нічого не казати, зберу і так.",
]
ПИТАННЯ, ВИ = re.compile(r"[?？]"), re.compile(r"\b(ви|вас|вам|вами|ваш\w*)\b|[а-яіїєґ]{2,}[еєиї]те\b|[а-яіїєґ]{3,}(йте|іть)\b", re.I)
ЧОЛ = re.compile(r"\bя\s+(?:вже\s+|сам\s+)?[а-яіїєґ]{2,}(?:в|ий)\b|\bя\s+міг\b", re.I)
вади = lambda с: sum(bool(р.search(с)) for р in (ПИТАННЯ, ВИ, ЧОЛ))
порада = lambda м, т: (м.порада_чиста(getattr(м, "жінці", lambda x: x)(т), ТЕМИ)[0]
                       if hasattr(м, "порада_чиста") else т)
дс = пс = 0
print("ПОРАДА І РЕПЛІКА В ЧАТІ · вади: питання / «ви» / чоловічий рід про себе")
for т in РЯДКИ:
    d, a = порада(ДО, т), порада(ПІСЛЯ, т); дс += вади(d); пс += вади(a)
    print("  вхід : %s\n   ДО (%d) %s\n   ПІСЛЯ (%d) %s" % (т[:76], вади(d), d[:130], вади(a), a[:130]))
print("вад лишилось: ДО %d → ПІСЛЯ %d" % (дс, пс))
print("порада-питання переписана словами коду: %s · м'яке запрошення промпта лишилось як було: %s"
      % ("так" if порада(ПІСЛЯ, РЯДКИ[0]).startswith("Якщо хочеш") else "НІ",
         "так" if порада(ПІСЛЯ, РЯДКИ[3]) == РЯДКИ[3] else "НІ"))
ПРОЗА = {"версія": "ОПИС_ВІДПОВІДЬ_V1", "текст": "Я підібрав для вас спокійний образ: у вас сьогодні офіс.",
         "як_носити": ["Заправте сорочку, якщо хочете видовжити ноги.", "Візьміть ремінь у тон."]}
р = РВ.опис_відповідь_з_json(json.dumps(ПРОЗА, ensure_ascii=False))
print("ПРОЗА КАРТКИ (`текст` + `як_носити` — те, що читає жінка):")
for с, a in zip([ПРОЗА["текст"]] + ПРОЗА["як_носити"], [р["текст"]] + р["як_носити"]):
    print("  ДО (%d) %s\n  ПІСЛЯ (%d) %s" % (вади(с), с, вади(a), a))
