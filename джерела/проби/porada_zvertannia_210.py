"""З-3, З-4, З-5в (рядок 210): форму поради, звертання й рід тримає КОД, не промпт.
Жива локальна модель (`qwen/qwen3.5-9b`, сід 7, знімок `z3_z4_porada_pytanniam_vy_seed7.jpg`)
прислала пораду двома питаннями, перейшла на «ви» й сказала про себе «Я підібрав».
ДО — `паспорт_нагоди` з origin/main, ПІСЛЯ — робоче дерево; ті самі рядки моделі.
Рядки — з `аудит/тести/2026-09-24_прохід_1.md` (сирих `vidpovidi/` у git нема).
Запуск із теки `джерела`: PYTHONPATH=. python3 проби/porada_zvertannia_210.py"""
import re, subprocess, sys, types; sys.path.insert(0, ".")
import паспорт_нагоди as ПІСЛЯ
ДО = types.ModuleType("пн_до")
ДО.__dict__["__name__"] = "пн_до"
exec(subprocess.run(["git", "show", "origin/main:джерела/паспорт_нагоди.py"],
                    capture_output=True, text=True).stdout, ДО.__dict__)
ТЕМИ = ["мета", "макіяж", "прикраси"]
РЯДКИ = [
    "Оскільки це ранковий діловий час у офісі, я б підбрала зручну тканину для повільного "
    "руху: чи ви обранете класичні брюки/спідницю, чи жодної прикраси не хочете?",
    "Я підібрав охайні буденні образи — сьогодні у вас робочий день в офісі.",
    "Я зрозуміла: сьогодні у вас робочий день в офісі.",
    "Якщо хочеш, підкажи, чи хочеш сьогодні бути помітною, чи буде яскрава помада і які "
    "прикраси любиш з таким образом — а можна й нічого не казати, зберу і так.",
]
ПИТАННЯ, ВИ = re.compile(r"[?？]"), re.compile(r"\b(ви|вас|вам|вами|ваш\w*)\b|[а-яіїєґ]{2,}[еєиї]те\b", re.I)
ЧОЛ = re.compile(r"\bя\s+(?:вже\s+|сам\s+)?[а-яіїєґ]{2,}(?:в|ий)\b|\bя\s+міг\b", re.I)
def міра(м, т):
    """(текст після модуля, скільки з трьох вад лишилось)."""
    п = getattr(м, "порада_чиста", None)
    с = (п(getattr(м, "жінці", lambda x: x)(т), ТЕМИ)[0] if п else т)
    return с, sum(bool(р.search(с)) for р in (ПИТАННЯ, ВИ, ЧОЛ))
дс = пс = 0
print("рядків моделі: %d · вади: питання / «ви» / чоловічий рід про себе" % len(РЯДКИ))
for т in РЯДКИ:
    d, dn = міра(ДО, т); a, an = міра(ПІСЛЯ, т); дс += dn; пс += an
    print("  вхід : %s\n   ДО (%d вади) %s\n   ПІСЛЯ (%d вади) %s" % (т[:78], dn, d[:150], an, a[:150]))
print("вад лишилось: ДО %d → ПІСЛЯ %d" % (дс, пс))
print("порада-питання переписана словами коду: %s" % ("так" if міра(ПІСЛЯ, РЯДКИ[0])[0].startswith("Якщо хочеш") else "НІ"))
print("м'яке запрошення, яке промпт і просить, лишилось як було: %s"
      % ("так" if міра(ПІСЛЯ, РЯДКИ[3])[0] == РЯДКИ[3] else "НІ"))
