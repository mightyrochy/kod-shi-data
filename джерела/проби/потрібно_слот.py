# -*- coding: utf-8 -*-
"""«потрібно» моделі — {слот, опис}. Чи шукає код річ у слоті, який назвала модель, чи будь-де за словами опису?
Запити — дослівно з живого прогону «Ір, собаки» (gemma-4-12b, сід 13, 25.09): ремонт руки 1 попросив сумку, складання
руки 2 — теплий верхній шар. Пул — рука 1 пакета `стенд_вх.json`; відповідь складання — 3 образи з пулу і це «потрібно».
Друкує факт: на кожен запит — у які слоти стали знайдені речі (`запропоновано`) і скільки з них у названому слоті.
Запуск: cd джерела && python3 проби/потрібно_слот.py"""
import collections, json, os, sys
Д = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, Д); os.chdir(Д)
import bridge as B
ЗАПИТИ = [dict(слот="сумка", опис="Для прогулянки з собаками сумка є обов'язковою для зручності, додайте її до образу."),
          dict(слот="верхній_шар", опис="Більш теплий верхній шар для температури 9°C (наприклад, куртка або щільний кардиган).")]
вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["гілка"] = 0
пул = json.loads(json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))["руки"]["1"])["пул"]
н = lambda с, k: пул[с][k % len(пул[с])]["н"]
образи = [dict(ід="о%d" % (і + 1), речі=[н("верх", і), н("низ", і), н("взуття", і), н("сумка", і)]) for і in range(3)]
в = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=json.dumps(dict(версія="1", образи=образи, потрібно=ЗАПИТИ),
                                                                                 ensure_ascii=False)), ensure_ascii=False)))
зн = в.get("запропоновано") or []
кат = {r.get("id"): r for r in B.каталог_останнього_пакета()}
стає = lambda р, с: р.get("слот") == с or с in ((кат.get(р.get("id")) or {}).get("слоти_альт") or ())
print("ФАКТ · слоти пулу руки 1: %s" % ", ".join(пул))
for з in ЗАПИТИ:
    мої = [р for р in зн if р.get("запит") == з["опис"]]
    сл = collections.Counter(р.get("слот") for р in мої)
    print("ФАКТ · запит у слоті «%s»: знайдено %d · слоти знайденого: %s · стають названим слотом: %d" % (
        з["слот"], len(мої), ", ".join("%s %d" % кв for кв in сл.items()) or "—", sum(стає(р, з["слот"]) for р in мої)))
    for р in мої:
        print("        %s · %s" % (р.get("слот"), str(р.get("назва"))[:70]))
