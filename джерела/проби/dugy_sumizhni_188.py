def дуга(сл, суміжна):
    """Дуга слова `сл`: `суміжна` — чинне правило; False — як було до Л-18 (прогалина й на краю)."""
    межі, вхід = list(V.ЛЕКСИКОН[сл][4]), [p[2][2] for p in т[сл].values() if p[2][1] > V.ДРІЖ_AB]
    for бік, знак in ((0, -1), (1, 1)):
        назовні = lambda h, від: (від - h) % 360 if знак < 0 else (h - від) % 360
        край, новий = V.ЛЕКСИКОН[сл][4][бік], V.ЛЕКСИКОН[сл][4][бік]
        порожніх = V.ВЖИТОК_ПРОГАЛИНА if суміжна else 0
        while порожніх <= V.ВЖИТОК_ПРОГАЛИНА and (межі[1] - межі[0]) % 360 + V.ВЖИТОК_КРОК <= V.ВЖИТОК_ДУГА_МАКС:
            у = [h for h in вхід if 0 < назовні(h, край) <= V.ВЖИТОК_КРОК]
            новий, порожніх = (max(у, key=lambda h: назовні(h, V.ЛЕКСИКОН[сл][4][бік])), 0) if у else (новий, порожніх + 1)
            межі[бік], край = новий, (край + знак * V.ВЖИТОК_КРОК) % 360
    return (межі[0] % 360, межі[1] % 360)
