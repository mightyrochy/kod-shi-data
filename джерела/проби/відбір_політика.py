"""Дози перетинних ознак і незалежність запиту від перестановки входу."""
import sys, pathlib, collections, copy
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import семплер as С, selection_policy as П, порядок_запиту as З, протокол as Р

def main():
    """Надрукувати вимір квот і перестановок на перетинних ознаках."""
    речі = [dict(id=str(i), н=str(i), гілка="на межі" if i < 8 else "ядро") for i in range(50)]
    for i, r in enumerate(речі):
        if i < 8: речі[i] = r = П.з_дозою(r, "на межі", 3)
        if i < 4 or 10 <= i < 18: речі[i] = r = П.з_дозою(r, "нижче смуги", 4)
        if i < 3 or 20 <= i < 26: речі[i] = П.з_дозою(r, "блиск", 3)
    речі[0][С.ПОЛЕ_УТРИМАННЯ] = True
    оригінал = copy.deepcopy(речі)
    for сід in range(1, 101):
        вибір = С.вибрати_зі_слота(речі, 20, сід)
        дози = collections.Counter(г for r in вибір for г in П.дози(r))
        assert len(вибір) == len({r["id"] for r in вибір}) == 20, (сід, len(вибір))
        assert дози == {"на межі": 3, "нижче смуги": 4, "блиск": 3}, (сід, дози)
        assert речі[0] in вибір and речі == оригінал
        assert З.перемішати(речі, сід) == З.перемішати(list(reversed(речі)), сід)
    суд = {Р.ВЕРДИКТ_ОБРАЗІВ: [{Р.ТВІЙ_ОБРАЗ: {"ід": str(i), "речі": [str(i), "спільна"]}} for i in range(10)]}
    for сід in range(1, 101):
        а, _ = З.перемішати_дріт(суд, сід, "select", образи=True)
        б, _ = З.перемішати_дріт({Р.ВЕРДИКТ_ОБРАЗІВ: list(reversed(суд[Р.ВЕРДИКТ_ОБРАЗІВ]))}, сід, "select", образи=True)
        assert а == б
    нижні = [П.з_дозою(dict(id=str(i)), "нижче смуги", 2) for i in range(30)]
    assert len(С.вибрати_зі_слота(нижні, 20, 3)) == 20
    н = П.намір("comfort_first", ["context"])
    assert н["каблук_стеля"]
    print("100 сідів: квота20; межа3, нижня4, блиск3; утримання та вхід збережено; 200 перестановок тотожні")

if __name__ == "__main__":
    main()
