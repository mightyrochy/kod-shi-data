# -*- coding: utf-8 -*-
"""Проба РЗ-2: промпти ПОВТОРУ ЗА ПРИЧИНОЮ на 40 речах пілоту — без моделі.
Будує `завдання_повтору` для кожної речі пілотного переліку, друкує, скільки речей іде ходом
«рядок» (переписати лише `features`) і скільки «повний» (розбір із приміткою), середню довжину
промпта кожного ходу проти промпта першого розбору тих самих речей і один приклад кожного ходу.
Запуск: python3 джерела/проби/повтор_промпт.py [перелік] [тека прогону]"""
import json, os, sys
ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(ТУТ))
import каталог_розбір as КР, каталог_розбір_прогін as П, фід_каталог as ФК, фід_розбір as ФР
ТЕКА = os.path.join(ТУТ, "..", "..", "аудит", "розбір_каталогу", "mamaylm-gemma-3-12b-it-v2.0_uk_povnyi")
перелік = sys.argv[1] if len(sys.argv) > 1 else ТЕКА + "_pilot/" + П.ПОРУШНИКИ_ФАЙЛ
тека = sys.argv[2] if len(sys.argv) > 2 else ТЕКА
причини = П.причини_з(перелік)
розбір = json.load(open(os.path.join(тека, "розбір.json"), encoding="utf-8"))
групи = {р["id"]: р["група"] for р in json.load(open(os.path.join(тека, "прогін.json"), encoding="utf-8"))["речі"]}
офери = {o["id"]: o for o in ФР.читати_yml(ФК.каталог_на_диску(), показ=False)[0] if o["id"] in причини}
ходи, приклад = {}, {}
for ід, пр in sorted(причини.items()):
    хід, повід, макс = П.завдання_повтору(офери[ід], пр, розбір.get(ід), групи[ід])
    текст = json.dumps(повід, ensure_ascii=False, indent=1)
    перший = len(json.dumps(КР.промпт(офери[ід]), ensure_ascii=False, indent=1))
    ходи.setdefault(хід, []).append((len(текст), перший, макс))
    приклад.setdefault(хід, (ід, пр, текст))
print("речей %d з %d у переліку (решти нема в каталозі на диску)" % (len(офери), len(причини)))
for хід, д in sorted(ходи.items()):
    print("хід %-4s: речей %2d · промпт %5.0f знаків у середньому (перший розбір тих самих речей %5.0f, %.0f %%) · стеля токенів %s"
          % (хід, len(д), sum(а for а, _, _ in д) / len(д), sum(б for _, б, _ in д) / len(д),
             100.0 * sum(а for а, _, _ in д) / sum(б for _, б, _ in д), д[0][2] or П.МАКС_ТОКЕНІВ))
ід, пр, текст = приклад[П.ХІД_РЯДОК]
print("\n── приклад ходу «рядок»: %s %s\n%s" % (ід, ",".join(пр), текст))
ід, пр, текст = приклад[П.ХІД_ПОВНИЙ]
print("\n── приклад ходу «повний»: %s %s — примітка:\n%s" % (ід, ",".join(пр), текст[текст.rindex('"примітка_повтору"'):]))
