"""Проба (рядок 2244): −10 °C, сніг, 20 хв пішки (П8 живого прогону пачки 2) — рука 1, заглушка.
Пул (`запити`, каталог_повний): верхніх шарів, справжніх пальт (`суд_погода.пальта_пулу`) і
нетеплих (мітка «частково» / «майже ні» / «ні» без утеплювача, оголошеного словом). Далі
`від_моделі` над образом футболка + низ + взуття + сумка + нетеплий верхній шар із пулу: рядок
K-WEA-01 «тепло несе саме пальто» — регістр. Червоне — «репліка» (вибір пропускає куртку в мороз),
зелене — «гейт» (ремонт заміною з пулу). Моделі не кличе. Запуск: python3 джерела/проби/мороз_2244.py"""
import json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed as Ф, bridge as B, міст_пакет as МП, верхнє_погода as ВП                     # noqa: E401
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), каталог=Ф.каталог_на_диску("каталог_повний.xml"), гілка=0)
вх["сценарій"] = dict(вх["сценарій"], темп_c=-10, опади="сніг")
вх["випадок"] = "робочий день, офіс, 09:00, −10 °C, сніг, 20 хв пішки"
B.виклик("запити", json.dumps(вх, ensure_ascii=False))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
п = [p for p in МП._КЕШ_ПАКЕТА.values() if p.get("кандидати")][0]["кандидати"]
def мітка(r):
    return (ВП.ТЕПЛОВІ_ФУНКЦІЇ.get(r.get("тип_верхнього") or r.get("тип")) or ("?",))[0]
вш = [кат.get(r["id"], r) for r in п.get("верхній_шар") or [] if "верхній_шар" not in (r.get("слоти_альт") or ())]
нетеплі = [r for r in вш if мітка(r) in ("частково", "майже ні", "ні")
           and not (isinstance(r.get("наповнювач"), str) and r["наповнювач"].strip())]
print("пул −10 °C: верхніх шарів %d · теплих (мітка «тепло») %d · нетеплих без утеплювача %d"
      % (len(вш), sum(мітка(r) == "тепло" for r in вш), len(нетеплі)))
print("  нетеплі:", "; ".join("%s [%s]" % (r["назва"][:30], r.get("тип_верхнього") or r.get("тип")) for r in нетеплі))
база = [next(c["id"] for c in кат.values() if c.get("слот") == с and (с != "верх" or c.get("тип") == "футболка"))
        for с in ("верх", "низ", "взуття", "сумка")]
for к in нетеплі[:3]:
    о = ((json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=база + [к["id"]]), ensure_ascii=False)))
          .get("вердикт") or {}).get("образи") or [{}])[0]
    р = [z for z in о.get("знахідки") or [] if z.get("правило") == "K-WEA-01" and "пальто" in z.get("суть", "")]
    print("  %-34s %-9s → K-WEA-01 «тепло несе пальто»: %s" % (к["назва"][:34], мітка(к),
          ", ".join("%s/%s %.2f" % (z["сила"], z["регістр"], z["сила_нп"]) for z in р) or "НЕМА"))
    print("     ", "ЗЕЛЕНЕ" if р and all(z["регістр"] == "гейт" for z in р) else "ЧЕРВОНЕ")
