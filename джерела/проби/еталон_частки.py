# -*- coding: utf-8 -*-
# Еталон правди про речі каталогу (РЗ-Е, рядок 404): 60 речей, правду кожного поля суддя записав очима з фото картки.
# Без аргументів — частки вердиктів по полях і джерелах: (а) текст крамниці, (б) продукт сьогодні (словники + фото v2),
# (в) фото-збагачення qwen3-vl, (г) розбір MamayLM. З аргументом <розбір.json> — той самий суд над БУДЬ-ЯКИМ новим розбором.
import sys, os, json, collections
Е = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'еталон_розбору.json'), encoding='utf-8'))
ПОЛЯ, ВИД = Е['поля'], ('правильно', 'хибно', 'вигадано', 'невідомо', 'не судиться', 'нема поля')
def суд(правда, опора, в, текстова=True):
    """Вердикт коду: правильно / хибно / вигадано (текст про це поле мовчить, а код хибний чи фото нічого не каже) /
    невідомо (джерело чесно мовчить) / не судиться (з фото не видно, а текст крамниці це каже)."""
    if в in (None, 'unknown', []) or правда in ('НВ', 'НЗ'):
        return 'невідомо' if в in (None, 'unknown', []) else 'не судиться' if в in опора else 'хибно' if опора else 'вигадано'
    добре = (len(в) == len(правда) and all(any(т in ч for т in в) for ч in правда) if правда and isinstance(правда[0], list)
             else в in правда)                         # частини комплекту: кожна частина — свій перелік типів
    return 'правильно' if добре else ('вигадано' if текстова and not опора else 'хибно')
def з_розбору(р, взуття):
    """Запис `розбір.json` → коди полів еталону: у взуття довжина — халява; тканина, а коли її нема, — матеріал верху."""
    ч = lambda к: None if р.get(к) in (None, 'unknown', 'none') and к != 'metal' else р.get(к)
    return dict(slot=ч('slot'), item_type=ч('item_type'), length=ч('shaft' if взуття else 'length'), sleeve=ч('sleeve'),
                neckline=ч('neckline'), cut=ч('cut'), fabric=ч('fabric') or ч('material'), pattern=ч('pattern'), color=ч('color_main'),
                shine=(р.get('veto') or {}).get('shine'), metal=ч('metal'), set_parts=sorted(п.get('item_type') for п in р.get('set_parts') or []))
лік, деталь = collections.defaultdict(collections.Counter), collections.Counter()
нове = json.load(open(sys.argv[1], encoding='utf-8')) if len(sys.argv) > 1 else None
for р in Е['речі']:
    if нове is not None and р['id'] in нове:
        к = з_розбору(нове[р['id']], 'shoes' in р['правда']['slot'])
        р['вердикти'] = {'нове': {п: суд(р['правда'][п], р['опора'].get(п, []), к[п]) for п in ПОЛЯ}}
        р['features']['деталь'] = any(с in (нове[р['id']].get('features') or '').lower() for с in р['ключі'])
    for дж, вс in (р['вердикти'] if нове is None or р['id'] in нове else {'нове': {'_': 'нема запису'}}).items():
        for п, в in вс.items(): лік[дж][в] += 1; лік[дж, п][в] += 1; лік[дж, р['група']][в] += 1
    деталь['є'] += р['features']['деталь']; деталь['вигадка'] += bool(нове is None and р['features']['вигадка'])
частка = lambda c, к: '%3.0f%%' % (100 * c[к] / max(1, sum(c[в] for в in ВИД[:3])))
for дж in [д for д in лік if isinstance(д, str)]:
    print('(%s) поставлено кодів %d: правильно %s, хибно %s, вигадано %s · мовчазні 20: правильно %s, вигадано %s · %s' % (
        дж, sum(лік[дж][в] for в in ВИД[:3]), частка(лік[дж], 'правильно'), частка(лік[дж], 'хибно'), частка(лік[дж], 'вигадано'),
        частка(лік[дж, 'мовчазна'], 'правильно'), частка(лік[дж, 'мовчазна'], 'вигадано'), dict(лік[дж])))
    print('   ' + ' · '.join('%s %s/%s' % (п, частка(лік[дж, п], 'правильно'), частка(лік[дж, п], 'вигадано')) for п in ПОЛЯ))
print('головна деталь у рядку features: %d/%d · %s' % (деталь['є'], len(Е['речі']), 'ключовими словами еталону (очима на (г): 33)'
      if нове else 'суддя очима; рядків з вигадкою %d' % деталь['вигадка']))
