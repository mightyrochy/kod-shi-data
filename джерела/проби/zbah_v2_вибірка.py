# -*- coding: utf-8 -*-
"""Проба збагачення v2: що дала вибірка 60 речей (аудит/збагачення_v2_вибірка.json).

Друкує факт, а не вердикт: скільки речей виміряно, чия маска, і як часто сім'я
тону ВИМІРУ та сім'я СЛОВА МОДЕЛІ збігаються з будь-яким словом крамниці.
Слово крамниці — не істина (див. ЗБАГАЧЕННЯ_ЗВІТ), тож це звірка свідків, а не точність.
"""
import collections, io, json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ)
from звірка_збагачення import сім_я_слова

д = json.load(io.open(os.path.join(ТУТ, "аудит", "збагачення_v2_вибірка.json"), encoding="utf-8"))
речі = д["речі"]
ок = [р for р in речі if "помилка" not in р]
сім = lambda с: сім_я_слова(с) if с else None
кр = [р for р in ок if р.get("слова_крамниці")]
збіг = lambda слово, р: сім(слово) in {сім(с) for с in р["слова_крамниці"]}
вимір = sum(збіг(((р.get("запис") or {}).get("колір_основний") or {}).get("слово"), р) for р in кр)
модель = sum(збіг(р["поля"].get("слово_моделі"), р) for р in кр)
маски = collections.Counter("ATR" if р["маска"]["чому"].startswith("ATR") and "→" not in р["маска"]["чому"]
                            else "запасна" for р in ок if р.get("маска"))
print("речей %d · збоїв %d · виміряно %d" % (len(речі), len(речі) - len(ок),
                                             sum(1 for р in ок if (р.get("вимір") or {}).get("кластери"))))
print("маска: %s · поправка експозиції за білим тлом: %d" % (dict(маски),
      sum("експозиція" in р["маска"]["чому"] for р in ок if р.get("маска"))))
print("сім'я ВИМІРУ ∈ сім'ї слів крамниці: %d/%d" % (вимір, len(кр)))
print("сім'я СЛОВА МОДЕЛІ ∈ сім'ї слів крамниці: %d/%d" % (модель, len(кр)))
print("спір вимір↔модель: %d · другий колір: %d" % (sum(1 for р in ок if р.get("спір")),
      sum(1 for р in ок if (р.get("запис") or {}).get("колір_другий"))))
for р in речі:
    if "помилка" in р:
        print("  збій %s (%s): %s" % (р["id"], р.get("слот"), р["помилка"][:60]))
