"""Рядок 1990 (п.12): що ярус R-LNG-UA мовної брами (`language_gate.перевірити`) і `назва_речі.чужа_мова`
кажуть про НАЗВИ каталогу (`каталог_повний.xml`) — скільки назв «російські» і які; плюс три рядки
наряду: «Кофта з вовни», «Шерсть мериноса», «Брюки и сапоги…». Друкує лічбу й до 6 прикладів.
Запуск із `джерела`: python3 проби/мова_брама_каталог.py"""
import collections, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import feed, language_gate as LG, назва_речі as НР
назви = sorted({str(o.get("назва") or "") for o in feed.читати_yml(feed.каталог_на_диску())[0]} - {""})
укр = lambda т: any(п["правило"] == LG.ЯРУС_УКРАЇНСЬКОЇ for п in LG.перевірити(т)["порушення"])
for т in ("Кофта з вовни", "Шерсть мериноса", "Брюки и сапоги в тон, сумка через плечо"):
    print("  %-42s R-LNG-UA=%s · чужа_мова=%s" % (т, укр(т), НР.чужа_мова(т)))
брама = [н for н in назви if укр(н)]
чужі = collections.Counter(str(НР.чужа_мова(н)).split(":")[0] for н in назви if НР.чужа_мова(н))
print("назв %d · R-LNG-UA на назві %d · чужа_мова %s" % (len(назви), len(брама), dict(чужі) or 0))
for н in брама[:6]:
    print("   брама:", н[:70])
