# -*- coding: utf-8 -*-
"""Читачі зон: той самий крій без шару, під відомим і під невідомим покриттям."""
if __name__ == "__main__":
    import os, sys
    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    import outfit as О, місце_речі as М
    топ = dict(id="топ", слот="верх", назва="топ без рукавів", виріз="відкритий",
               виріз_тип="V-подібний", рукав_рівень="без рукавів")
    шар = dict(id="шар", слот="верхній_шар")
    збої = 0
    for назва, річ, шар_на_ній, зони, вето in (
        ("без шару", топ, None, {"руки", "декольте"}, {"руки", "плечі", "декольте"}),
        ("під невідомим шаром", топ, шар, set(), set()),
        ("не видно", dict(топ, місце_стилістки=dict(видно="ні")), шар, set(), set()),
        ("видно цілком", dict(топ, місце_стилістки=dict(видно="так")), шар,
         {"руки", "декольте"}, {"руки", "декольте"}),
        ("розстебнутий довгий рукав", топ, dict(шар, рукав_рівень="довгий",
         місце_стилістки=dict(розстебнуто="так")), {"декольте"}, {"декольте"}),
        ("застебнутий довгий рукав", топ, dict(шар, рукав_рівень="довгий",
         місце_стилістки=dict(розстебнуто="ні")), set(), set()),
        ("маска: сховано", dict(топ, місце_виміру=dict(видно=0.0)), шар, set(), set()),
        ("закритий крій", dict(топ, назва="светр", виріз="закритий", виріз_тип="стійка",
         рукав_рівень="довгий"), None, set(), set()),
        ("жилет не є голим тілом", dict(шар, назва="укорочений жилет без рукавів"), None, set(), set()),
    ):
        р = dict(річ, місце_речі=М.записати(річ, шар_на_ній))
        факт = (О.зони_речі(р)[0], О.зони_вето_з_кодів(р)[0])
        добре = факт == (зони, вето)
        print(назва, факт, "OK" if добре else "ЗБІЙ")
        збої += not добре
    р = dict(топ, місце_речі=М.записати(топ, шар))
    assert any("невідомо" in ч for ч in О.зони_речі(р)[1])
    assert О.зони_речі(топ)[0] == {"руки", "декольте"}
    assert О.зони_вето_з_кодів(топ)[0] == {"руки", "плечі", "декольте"}
    print("збоїв:", збої)
    sys.exit(bool(збої))
