"""K-WEA-03 (темне + пряме сонце + облягання): `python3 проби/wea_K-WEA-03.py`.

ЧОМУ БУЛО «БЕЗ СЛІДУ» — ДВІ ПРИЧИНИ, І ЖОДНА НЕ В САМОМУ ПРАВИЛІ.
1. `сонце` не стояло в `сценарій.ПОЛЯ`, хоч `profile.ПОГОДА_КОНТРАКТ` його
   оголошує, а `суд_образу.review` приймає: шов викидав ключ як незнайомий.
2. `прилягання` не писав НІХТО, і `outfit.елементи` ставила «skim» на 100 %
   речей — цикл правила відсівав кожну першим рядком.
ЩО ПОКАЗУЄ ПРОБА: обидва входи доїхали, і темна річ приляглого крою на сонці
дає рядок у вердикті; та сама річ без прапорця сонця його не дає."""
import sys, pathlib, json
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import feed as Ф, bridge as B, colorspace as КС, silhouette as СИЛ, outfit as O

вх = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml"); вх["гілка"] = 0
вх["сценарій"].update(темп_c=28, опади="ні", сонце=True)
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
тем = [c for c in кат if c.get("слот") in ("верх", "сукня")
       and СИЛ.прилягання_за_кроєм(O.крій_речі(c)) == "cling"
       and c.get("lab") and КС.lch(c["lab"])[0] < 45]
print("речей «темне × приляглий крій» у каталозі пакета:", len(тем))
ціль = тем[0]
взут = next(c for c in кат if c.get("слот") == "взуття")
print("річ:", ціль["назва"][:50], "· крій", O.крій_речі(ціль),
      "· L*%.0f" % КС.lch(ціль["lab"])[0])
for підпис, сонце in (("сонце=True", True), ("сонце=False", False)):
    вх["сценарій"]["сонце"] = сонце
    вм = json.loads(B.виклик("від_моделі", json.dumps(
        dict(вх, ід=[ціль["id"], взут["id"]]), ensure_ascii=False)))
    о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
    з = next((z for z in (о.get("знахідки") or []) if z.get("правило") == "K-WEA-03"), None)
    print("%-12s K-WEA-03:" % підпис, "НЕМА" if not з else
          "%s %.2f · %s · %s" % (з["сила"], з["сила_нп"], з["суть"][:44], з["регістр"]))
