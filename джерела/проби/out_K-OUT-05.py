# -*- coding: utf-8 -*-
"""K-OUT-05 (над кравецтвом покриття — ворота, не преференція).

ЧОМУ СЛІДУ НЕ БУЛО: правило вмикається ПАРОЮ з оголошеними довжинами — жакет у
слоті «верх» (тип «блейзер»/«костюм») і верхній шар, чий край ВИЩЕ жакетового.
У каталозі рівень довжини оголошено на 326 із 618 верхніх речей і лише на 72 із
303 блейзерів, а ядро образу батареї («сукня+низ+взуття+сумка») жакета не бере
взагалі. Отже пара, задля якої правило написане, у прогонах не складалась.
ЩО ПОКАЗУЄ ПРОБА: пара з каталогу — пальто до стегна над блейзером до литки —
і рядок «жакет визирає з-під пальта» у `вердикт.образи[0].знахідки`."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, outer as OU, fit as ПС

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
вх["сценарій"].update(темп_c=5, опади="ні")
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
к = з["кандидати"]
T = ПС.тіло(вх["зріст"], вх["обхвати"])
пальто = next(c for c in кат.values() if c.get("слот") == "верхній_шар"
              and c.get("довжина_рівень") == "стегно")
жакет = next(c for c in кат.values() if c.get("слот") == "верх"
             and c.get("тип") in ("блейзер", "костюм")
             and c.get("довжина_рівень") == "литка")
print("пальто: %s · край %.1f см" % (пальто["назва"][:44], OU.край_см(пальто, T)[0]))
print("жакет:  %s · край %.1f см" % (жакет["назва"][:44], OU.край_см(жакет, T)[0]))
ід = [пальто["id"], жакет["id"]] + [(к.get(сл) or [{}])[0].get("id")
                                    for сл in ("низ", "взуття") if (к.get(сл) or [])]
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
р = next((z for z in (о.get("знахідки") or []) if z.get("правило") == "K-OUT-05"), None)
print("K-OUT-05 у вердикті:", "НЕМА" if not р else
      "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:58]))
print("речі рядка:", (р or {}).get("речі"), "· ремонт:", str((р or {}).get("ремонт"))[:52])
