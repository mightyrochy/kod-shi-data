"""ШКАЛА-1 (рядки 1530, 1551): у скількох промптах тексту для неї числа шкал (ошатність 1–10, бал фото)
їдуть без позначки «внутрішнє» (межа `без_шкал`;
довідка — `без_чисел_шкал`: підписи екрана з «app» вона цитує). До — ≥1, після — 0. Запуск: python3 проби/шкала_внутрішня.py"""
import json, re, sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import збирач_промптів as ЗП, розбір_відповідей as РВ, міст_стилістка as МС, міст_помічниця as МП
import оцінка_образу as ОО, мовний_шар as МШ

ЧИСЛО_ШКАЛИ = re.compile(r'"(formality|formality_from_photo|fo)": ?\[?\d')
МІТКИ = [м for м in (ЗП.МЕЖІ_EN.get("без_шкал"), ЗП.МЕЖІ_EN.get("без_чисел_шкал")) if м]
день = {"formality": [6, 8], "start_hour": 9}
промпти = {
    # картка й опис — один виклик (`ОПИС`): «Чому цей образ» пише він
    "опис (картка)": РВ.опис_v1([{"н": 1, "назва": "сукня", "слот": "сукня", "магазин": "x", "фото_номери": [1]}],
                                випадок={"нагода": "робота"}, день=день),
    "опис: case": ЗП.зібрати(РВ.ОПИС, {"outfit": {"items": [{"n": 1}]}, "case": {"formality": [5, 7]}}),
    "питання": ЗП.зібрати(МС.ПИТАННЯ, {"question": "q", "items": [{"formality": 6}], "case": {"formality": [6, 8]}}),
    "оцінка (пояснення)": ЗП.зібрати(ОО.ОЦІНКА, {"check": {"x": 1}, "outfit": ["a"], "items": [{"id": "a", "formality": 6,
                                                                       "formality_from_photo": 5}]}),
    "довідка": ЗП.зібрати(МП.ДОВІДКА, {"question": "q", "app": {"x": 1}, "state": {"case": {"formality": [5, 7]}}}),
    "розмова": ЗП.зібрати(МШ.РОЗМОВА, {"her_new_message": "q", "passport": {"formality": {"from": 5, "to": 7}}}),
}
без = 0
for імʼя, п in промпти.items():
    т = json.dumps(п, ensure_ascii=False)
    числа = bool(ЧИСЛО_ШКАЛИ.search(т) or '"formality": {"from": 5' in т)
    мітка = any(json.dumps(м, ensure_ascii=False)[1:-1] in т for м in МІТКИ)
    без += числа and not мітка
    print("%-20s числа шкали: %-3s позначка «внутрішнє»: %s" % (імʼя, "так" if числа else "ні", "так" if мітка else "НІ"))
print("промптів із числами шкал без позначки: %d з %d" % (без, len(промпти)))
