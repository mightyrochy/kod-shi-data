"""Повний каталог і граничні входи чотирьох аксесуарних файлів для звірки ваги."""
import gzip, json, os, pathlib


def набори():
    """Кожна річ каталогу × функції з місцями ваги; граничні входи — сітками."""
    import fit as ПС, аксесуари_носіння as Н
    вх = json.loads((pathlib.Path(__file__).resolve().parents[1] / 'стенд_вх.json').read_text(encoding='utf-8'))
    обх = {k: float(v) for k, v in вх['обхвати'].items()}
    T = ПС.тіло(float(вх['зріст']), обх)
    T2 = dict(T, виміряні_рівні=sorted(set(T.get('виміряні_рівні') or ()) | {'пах'}))
    with gzip.open(pathlib.Path(os.environ['TMP']) / 'е3_каталог.json.gz', 'rt', encoding='utf-8') as ф:
        каталог = json.load(ф)
    print('каталог', len(каталог), flush=True)
    yield 'без_входу', 'без_входу', [], {}
    низи = [р for р in каталог if р.get('слот') in ('низ', 'сукня', 'комплект') and Н.вага_полотна(р)[1]]
    важкий = max(низи, key=lambda р: Н.вага_полотна(р)[1])
    пари = [dict(id='пара-' + т, назва=т, слот='взуття', тип=т) for т in Н.МАСА_ВЗУТТЯ]
    for р in каталог:
        ід = str(р.get('id'))
        yield ід, 'перевірити', [T, [р]], {}
        yield ід + '@T2', 'подовження_ноги', [T2, [р]], {}
        yield ід + '@без', 'вартість_носіння', [[р]], {}
        for год, пов in ((г, п) for г in (2, 6, 9, 12) for п in (None, *Н.ПОВЕРХНІ)):
            yield '%s@%s/%s' % (ід, год, пов), 'вартість_носіння', [[р]], dict(тривалість_год=год, поверхня=пов)
        for ранг in (0.74, 0.75, 0.8, 0.9, 1.0):
            рр = dict(р, ціна_ранг=ранг, ціна_ранг_з=40, обхват_у_пулі=12)
            if р.get('слот') == 'взуття':
                рр['ремонтопридатна'] = ранг != 0.74 and ранг < 0.9
            yield '%s@ранг%s' % (ід, ранг), 'цінність_речей', [[рр]], {}
        if р in низи:
            yield ід + '@пари', 'маса_взуття', [[р] + пари], {}
        if р.get('слот') == 'взуття':
            yield ід + '@важкий', 'маса_взуття', [[важкий, р]], {}
    for h, год, пов in ((h, г, п) for h in range(26) for г in (1, 4, 6, 8, 12) for п in (None, *Н.ПОВЕРХНІ)):
        пара = dict(id='каблук%s' % h, назва='каблук', слот='взуття', тип='туфлі', каблук_см=h / 2)
        yield 'каблук%s@%s/%s' % (h, год, пов), 'вартість_носіння', [[пара]], dict(тривалість_год=год, поверхня=пов)
    for зр, см in ((з, с) for з in range(150, 191, 2) for с in range(300, 900, 5)):  # тіло без похибки: гілка K-EDG-01
        Т0 = ПС.тіло(float(зр), обх); Т0.update({к: dict.fromkeys(Т0[к], 0.0) for к in ('похибка_висот', 'похибка_ширин')})
        yield 'ремінь%s@%s' % (см, зр), 'перевірити', [Т0, [dict(id='сумка', назва='сумка', слот='сумка', ремінь_см=см / 10)]], {}
