"""Реєстр А (рядок 5630), клас А2: у каруселі картки — кадри іншої речі чи іншого варіанта, які
правило 7 (`чужий_підпис`, рядок 411) не бачить. Друкує по ряду картки після всіх правил:
(1) якір (кадр жнив) підписаний формою, а лишились кадри БЕЗ цієї форми — чий вони, з адреси не
видно (рядки 3890/3891); (2) кадру жнив у ряду нема, а кадри підписані різними товарами
(правило 7 не вмикається, рядок 3892); (3) кадри класу «інша_річ» у виміряних галереях.
Запуск: cd джерела && python3 проби/каталог_проблеми_а_чужі_в_галереї.py"""
import collections, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import feed as Ф, фід_фото as ФФ, фід_кадр_колір as ФКК
оф = Ф.читати_yml(Ф.каталог_на_диску("каталог_повний.xml"))[0]
зб, сп, хо = Ф.читати_збагачення(), ФФ._спільні_фото(оф), ФФ._хости_крамниць(оф)
без_форми, без_якоря = collections.Counter(), collections.Counter()
for o in оф:
    з, м = зб.get(o["id"]), o.get("магазин")
    к = з.get("фото") if isinstance(з, dict) else None
    р = ФФ.кадри_речі(o, сп.get(м) or {}, хо, к)
    якір = next((u for u in р if к and ФФ._файл_фото(u) == ФФ._файл_фото(к)), None)
    if якір:
        я = ФФ._підписи_адреси(якір, True)
        if я and any(set(я) - set(ФФ._підписи_адреси(u)) for u in р if u is not якір):   # бракує хоч однієї форми якоря
            без_форми[м] += 1
    elif len({tuple(sorted(ФФ._підписи_адреси(u).items())) for u in р if ФФ._підписи_адреси(u)}) > 1:
        без_якоря[м] += 1
print("(1) якір підписаний, лишились кадри без його форми підпису: %d речей ·" % sum(без_форми.values()), без_форми.most_common(6))
print("(2) кадру жнив у ряду нема, кадри підписані різними товарами: %d речей ·" % sum(без_якоря.values()), без_якоря.most_common(6))
іа = [ід for ід, вв in ФКК.читати_кадри().items() if any(в.get("клас") == "інша_річ" for в in вв)]
print("(3) виміряні галереї з кадром «інша_річ»: %d речей з %d" % (len(іа), len(ФКК.читати_кадри())))
