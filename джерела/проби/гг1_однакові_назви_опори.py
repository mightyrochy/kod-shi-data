"""Рядок 2242 (п.12): учасники опори K-ACC-01 — id, не назви. На `каталог_повний`: (а) скільки назв стоять у ≥2 слотах (з них
аксесуар у парі); (б) образи з пар таких однойменних речей різних слотів, де аксесуар відлунює гучну річ тієї самої назви (опора K-ACC-01
на справжніх рядках каталогу), — скільки з них після `міст_відповіді._опори_номерами` мають echo й accent ОДНИМ номером (злиття).
Запуск із джерела/ (каталог розпакований, ~1 хв): python3 проби/гг1_однакові_назви_опори.py"""
import json, sys, collections as K
sys.path.insert(0, "."); import bridge as B, аксесуари_структура as АС, реєстр_правил as РП, міст_відповіді as МВ
B.виклик("запити", json.dumps(json.load(open("стенд_вх.json", encoding="utf-8")), ensure_ascii=False)); кат = B.каталог_останнього_пакета()
С, Л = K.defaultdict(list), K.Counter()
for x in кат: С[x.get("назва")].append(x)
for назва, рр in С.items():
    if len({x.get("слот") for x in рр}) < 2: continue
    Л["(а) назв у ≥2 слотах"] += 1
    пари = [(а, о) for а in рр if а.get("слот") in АС.СЛОТИ_АКСЕСУАРІВ for о in рр if о.get("слот") != а.get("слот")]
    Л["(а) з них з аксесуаром у парі різних слотів"] += bool(пари); Л["(б) пар однойменних речей із аксесуаром"] += len(пари)
    for а, о in пари:
        оп = [z for z in РП.розділити_опори(АС.аксесуар_як_структура([dict(о), dict(а)]))[1] if z["правило"] == "K-ACC-01"]
        if not оп: continue
        ном = {о["id"]: (1, "00"), а["id"]: (2, "00")}; ном_о = dict(ном); ном_о.setdefault(назва, ном[о["id"]])  # як `_запис`
        уч = МВ._опори_номерами(оп, ном_о)[0]["учасники"]
        Л["(б) з них з опорою-відлунням K-ACC-01"] += 1; Л["(б) з них echo і accent одним номером"] += len({у["річ"] for у in уч}) < 2
Р = [dict(id=і, назва="Other Brand", слот=с, lab=[45.0, 60.0, 40.0]) for і, с in (("x1", "сукня"), ("x2", "сумка"))]   # синтетична пара
оп = РП.розділити_опори(АС.аксесуар_як_структура(Р))[1]
Л["(в) синтетична пара «Other Brand» сукня+сумка: номери учасників"] = [у["річ"] for у in МВ._опори_номерами(оп, {"x1": (1, "00"), "x2": (2, "01"), "Other Brand": (1, "00")})[0]["учасники"]] if оп else "опори нема"
for к, v in Л.items(): print("  %-46s %s" % (к, v))
