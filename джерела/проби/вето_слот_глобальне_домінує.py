"""Накопичення вето між ходами: глобальне («без принта» на весь образ) домінує над звуженим слотом
(«взуття без принта») в обох порядках; без слота в ході — запис у `вето_тверде.слоти` не з'являється.
Друкує `вето_тверде.слоти` після двох ходів (коментар до образу · хід розмови).
Прогін: cd джерела && python3 проби/вето_слот_глобальне_домінує.py"""
import os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import мовний_шар as МШ
ГЛ, ЗВУЖ = {"pattern": "print_generic", "quote": "без принта"}, {"slot": "shoes", "pattern": "print_generic", "quote": "без принта"}
def коментар(перший, другий):
    п = МШ.паспорт_з_коментаря({"vetoes": [перший]}, паспорт_досі={"перекладено_шаром": True, "вето": {}})["паспорт"]
    return МШ.паспорт_з_коментаря({"vetoes": [другий]}, паспорт_досі=п)["паспорт"]["вето_тверде"]["слоти"]
def шар(перший, другий):
    х1 = МШ.паспорт_з_шару({"vetoes": [перший]}, {}, слова_ходу="без принта")
    х2 = МШ.паспорт_з_шару({"vetoes": [другий]}, {}, паспорт_досі=х1["паспорт"], слова_ходу="без принта")
    return х2["паспорт"]["вето_тверде"]["слоти"]
for назва, а, б in (("глобальне → звужене", ГЛ, ЗВУЖ), ("звужене → глобальне", ЗВУЖ, ГЛ), ("звужене → звужене", ЗВУЖ, {"slot": "bag", "pattern": "print_generic", "quote": "без принта"})):
    print("%-22s коментар: %-34s шар: %s" % (назва, коментар(а, б), шар(а, б)))
