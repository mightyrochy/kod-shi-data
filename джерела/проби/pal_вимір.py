"""Спільний вимір для проб K-PAL: чи бере пул лише те, що взяли рядки запиту палітри.

Окремим файлом, бо його ставлять три проби (K-PAL-01, K-PAL-02, K-PAL-11), і
три копії однієї арифметики розійшлись би на першій же правці однієї з них.
ЩО САМЕ МІРЯЄТЬСЯ. Знаменник — речі пулу, чий колір ВИМІРЯНО і чий колір НЕ
нейтраль (K-COL-06: нейтраль законна під будь-яку схему — те саме рішення, що в
`pipeline.схема_образу`) і не метал палітри (K-PAL-11: фурнітура судиться
металом, не дугою). Чисельник — ті з них, кого БЕРЕ хоч один КОЛЬОРОВИЙ рядок
запиту їхнього слота (`palette.запит_у_фід`, він же `bridge.спец_останнього_пакета`),
і бере предикатом самого продукту: `feed.підходить` для виміряного кольору, а для
кольору-словом — `feed.частка_вікна > 0` разом із `feed.описує_річ`, бо слово
кольору — ЗОНА, а не точка (feed.py: «зону питали як точку», 0 із 5650).
Нейтральні й металеві рядки чисельника не дають: саме нейтральним рядком
хроматична річ їхала в пул своїм блідим краєм (86 із 97 — те, що лікував
`описує_річ`), і саме це правило має ловити.
ЧОМУ НЕ ВІКНО `палітра_практична` (виправлено 19.09.2026). Доти чисельник питав
ГЛОБАЛЬНЕ вікно людини (на стенді L 55–95) — вікно екрана палітри, яким добір
ніколи не ходив. Драбина світлоти йде ВІД обличчя НАВМИСНО (`palette.поверхи`:
«кроки світлоти мусять десь бути, отже кроки йдуть у низ і взуття»), тож вікно
секунданта L 30–39 лежить під палітровим цілком, і `запит_у_фід` для «низу»
чесно не має жодного рядка сім'ї палітри — перетин порожній. Поки колір УСІХ
хроматичних речей ядра походив зі слова (представник — центр вікна лексикону,
L 78.5), різниці не було видно; PR #126 («збагачення v2 у фід», 696 речей дістали
колір із фото) дав в'язаним штанам `ж-00944@maxa.ua` вимір L 31.9 — законний у
вікні свого слота, нижчий за палітрове — і проба почервоніла на здоровому пулі.
ГІЛКИ «на межі» І «розрив» РАХУЮТЬСЯ ОКРЕМО, а не проти правила: сміливий намір
(`composer.СМІЛИВІ_НАМІРИ`) заводить їх У ПУЛ НАВМИСНО, вони позначені в кожному
рядку пулу полем `гілка`, і модель їх бачить саме як вихід за палітру. Мірятися
K-PAL-01 має ЯДРО — те, що система пропонує як «її кольори».
АКСЕСУАРНІ СЛОТИ (`bridge.СЛОТИ_БЕЗ_ВІКНА`) НЕ РАХУЮТЬСЯ: їхні вікна система
розтягує на всю шкалу навмисно, і палітра над ними не діє за рішенням.
"""
import json, pathlib, sys
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
if str(_КОРІНЬ) not in sys.path: sys.path.insert(0, str(_КОРІНЬ))
import bridge as B, colorspace as cs, feed as Ф, pipeline as PL, palettes as PAL


def пул_стенда(гілка=0, **зміни):
    """(кандидати, каталог за id, спец, запити) — рівно те, чим ходив продукт."""
    вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
    вх["гілка"] = гілка
    вх.update(зміни)
    r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    спец, запити = B.спец_останнього_пакета()
    кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
    return r.get("кандидати") or {}, кат, спец, запити


def бере_рядок(п, lab, q):
    """Чи БЕРЕ цей рядок запиту цю річ — тим самим предикатом, що й добір.

    Колір-словом судиться зоною (`частка_вікна`) і родом рядка (`описує_річ`);
    виміряний колір — точкою (`підходить`). Дві істини не розводяться: обидві
    гілки — виклики `feed`, а не переписана тут копія його арифметики."""
    вікно = п.get("вікно") if п.get("джерело_кольору") == "назва_вікно" else None
    if вікно:
        в = (float(вікно[0]), float(вікно[1]), float(вікно[2]), float(вікно[3]),
             tuple(вікно[4]) if вікно[4] else None)
        return Ф.частка_вікна(в, q) > 0 and Ф.описує_річ(tuple(lab), q)
    return Ф.підходить(tuple(lab), q)


def частка_у_вікнах(кандидати, кат, спец, запити, гілка="ядро"):
    """(усередині, усього, {слот: (усередині, усього)}, запасом) — без нейтралей і металу.

    `гілка=None` — рахувати всі гілки разом; за замовчуванням лише «ядро».
    `запасом` — скільки з чисельника взяв лише рядок-гарантія слота (`спроба=1`,
    дуга схеми, розширена на 30°): він законний, але це вже не вікно палітри, і
    мовчати про нього означало б хвалити правило за роботу його запобіжника."""
    метал = ((спец or {}).get("палітра_практична") or {}).get("метал")
    усередині = усього = запасом = 0
    по_слотах = {}
    for слот, пул in (кандидати or {}).items():
        # ── АКСЕСУАРНІ СЛОТИ БЕЗ ВІКНА НЕ МІРЯЮТЬСЯ (18.09.2026) ──────────────
        # `bridge._розкрити_аксесуари` НАВМИСНО розтягує вікна цих слотів на всю
        # шкалу (крізь вікно проходило 7 сережок зі 134 — слот стояв порожній),
        # тож у ядро тут заходить прикраса будь-якого кольору, і правило палітри
        # над нею не діє за рішенням, а не за дефектом. Виміряно з жнивами v1:
        # усі 5 речей ядра поза вікнами були прикрасами (обручі #FFD700, емаль
        # #006400), а одяг — 4 з 4 усередині.
        if слот in B.СЛОТИ_БЕЗ_ВІКНА: continue
        рядки = [q for q in (запити or []) if q.get("слот") == слот
                 and not q.get("нейтраль") and not q.get("метал")]
        ок = n = 0
        for x in пул:
            if гілка is not None and (x.get("гілка") or "ядро") != гілка: continue
            п = кат.get(x.get("id")) or {}
            lab = п.get("lab")
            if not lab: continue
            L, C, h = cs.lch(lab)
            if PL._нейтральний_тон(h, C, L): continue
            м = PAL.метал_речі(lab, слот)
            if м and метал in (м, "обидва"): continue   # K-PAL-11 судить фурнітуру металом
            n += 1
            взяв = next((q for q in рядки if бере_рядок(п, lab, q)), None)
            if взяв is None: continue
            ок += 1
            запасом += 1 if взяв.get("спроба") else 0
        if n: по_слотах[слот] = (ок, n)
        усередині += ок; усього += n
    return усередині, усього, по_слотах, запасом
