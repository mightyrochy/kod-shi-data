# -*- coding: utf-8 -*-
"""Сценарії хронології спільного контракту згортання й читача зрізу."""
import згорнути_дошку as згортання
from дошка_зріз import читати_дошку


def перевірити_хронологію(дошка, фрагмент, рядок, нове, кінець):
    """Вимірює дати між блоками, проти дошки й нового рядка іншого фрагмента."""
    новий = фрагмент.with_name('новий.md')
    for стан in ('**ЧАСТКОВО**', '**ЗАКРИТО**'):
        for дата in ('2026-10-19', '2026-10-26', '2026-10-27'):
            закриття = стан + ' ' + кінець.replace('2026-10-26', дата)
            закритий = рядок(10187, закриття, нове)
            погана = дата < '2026-10-26'
            for вид in ('новий', 'заміна', 'стан дошки', 'стан збору'):
                дошка.write_text(рядок(1) + ('\n' + рядок(10187, поля=нове) if вид in ('заміна', 'стан дошки') else ''), encoding='utf-8')
                if вид == 'стан збору':
                    новий.write_text(рядок(10187, поля=нове), encoding='utf-8')
                текст = закритий if вид == 'новий' else 'заміна ' + закритий if вид == 'заміна' else 'стан 10187: ' + закриття
                фрагмент.write_text(текст, encoding='utf-8')
                до = (дошка.read_bytes(), фрагмент.read_bytes())
                помилки = згортання.згорнути(True)[1]
                assert bool(помилки) == погана, (вид, дата, помилки)
                assert not погана or any('поле дата-закриття:' in п for п in помилки), помилки
                assert до == (дошка.read_bytes(), фрагмент.read_bytes())
                if новий.exists():
                    новий.unlink()
            дошка.write_text(закритий, encoding='utf-8')
            try:
                читати_дошку(дошка)
            except ValueError as помилка:
                assert погана and 'поле дата-закриття:' in str(помилка), помилка
            else:
                assert not погана, 'зріз прийняв закриття до появи'
    print('Хронологія: 8 ранніх закриттів відхилено; 16 рівних/пізніших прийнято; зріз: 2 відхилено, 4 прийнято; перевірка нічого не записала')
