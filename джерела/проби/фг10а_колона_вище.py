"""«10 а» (рішення власника 28.09): при меті «вище» однотонна колона з голови до ніг
перемагає K-COL-01 «монохром — пласко». Друкує факт на РЕАЛЬНИХ кольорах каталогу:
скільки монохромних образів мають вердикт «площинно» при трьох старих метах і що
виходить при меті «вище».
Запуск із теки `джерела`: `python3 проби/фг10а_колона_вище.py`."""
import os, sys, collections
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as ФК, колір_світлота as КС, реєстр_правил as РП

кат = ФК._прочитати_каталог(feed.каталог_на_диску(), ліміт_фото=0)["каталог"]
за_слотом = collections.defaultdict(list)
for r in кат:
    if r.get("lab") and r.get("слот") in ("сукня", "взуття"):
        за_слотом[r["слот"]].append(r)
# ПЛОЩІ — ЧАСТКАМИ СЛОТА, не з геометрії: на живому шляху `перевірка_value` стоїть за
# гейтом площ (`суд_огляд`: `площі_є`), і виміряних країв фід не несе — це стенд правила.
ПЛОЩА = {"сукня": 0.62, "взуття": 0.16}
образи, крок, усіх = [], РП.C["step_min"], 0
for сукня in за_слотом["сукня"][:220]:
    for пара in за_слотом["взуття"][:60]:
        L1, L2 = сукня["lab"][0], пара["lab"][0]
        усіх += 1
        if abs(L1 - L2) >= крок:
            continue                      # не колона: два рівні світлоти
        образи.append([dict(річ=сукня["id"], слот="сукня", L=L1, площа=ПЛОЩА["сукня"],
                            текстура=сукня.get("текстура"), сім_я="нейтраль"),
                       dict(річ=пара["id"], слот="взуття", L=L2, площа=ПЛОЩА["взуття"],
                            текстура=пара.get("текстура"), сім_я="нейтраль")])
print("ПАР «сукня + взуття» з реального каталогу: %d · з них КОЛОНА (ΔL* < %.0f): %d (%.0f %%)"
      % (усіх, крок, len(образи), 100.0 * len(образи) / max(1, усіх)))
лічба = collections.Counter()
for E in образи:
    for мета in ("лестити", "приховати", "експресія", "вище"):
        for з in КС.перевірка_value(E, "conventional", мета):
            лічба[(мета, з["правило"], з["сила"])] += 1
for (мета, прав, сила), n in sorted(лічба.items()):
    print("  мета %-10s → %s %-8s ×%d" % (мета, прав, сила, n))
змінено = лічба[("вище", "K-COL-01", "hint")]
print("СУД ЗМІНИВСЯ на меті «вище» для %d із %d образів (%.0f %%): «площинно» strong → "
      "«лишити» hint" % (змінено, len(образи), 100.0 * змінено / max(1, len(образи))))
