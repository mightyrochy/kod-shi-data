"""К-CLR-02: відомий запис, невідоме місце й старий near, що суперечить запису."""
import sys
sys.path.insert(0, ".")
import outfit as О, колір_світлота as К, місце_речі as М

def головна():
    """Друкує рішення для трьох станів місця та невідомого проміжного кольору."""
    особа = dict(доступно=True, L_шкіри=75, value_gap=15)
    for слово, бік in (("так", True), ("ні", False), (None, None)):
        річ = dict(id="шарф", слот="шарф", hex="#111111", площа=0.1)
        if слово:
            річ["місце_стилістки"] = dict(біля_обличчя=слово, слова="як вдягнено")
        е = О.елементи([річ])[0]
        е["near"] = 0 if бік is True else 1  # старий шлях каже протилежне запису
        з = К.біля_обличчя([е], особа)
        факт = [(x["правило"], x["сила"]) for x in з]
        print("К-CLR-02", слово, "→", факт)
        assert bool(з) == (бік is not False)
        assert бік is not None or all(x["сила"] == "питання" and x["сила_нп"] == 0 for x in з)
        assert бік is not True or any(x["сила"] != "питання" for x in з)
    е = О.елементи([dict(id="сережки", слот="сережки", hex="#111111"),
                     dict(id="шарф", слот="шарф", hex="#aaaaaa")])
    з = К.біля_обличчя(е, особа)
    assert len(з) == 1 and з[0]["сила"] == "питання"  # невідомий буфер змінює весь ланцюг
    е = О.елементи([dict(id="верх", слот="верх", hex="#111111", near=1)])
    assert М.бік_межі(е[0]) is None and К.біля_обличчя(е, особа)[0]["сила"] == "питання"

if __name__ == "__main__":
    головна()
