# -*- coding: utf-8 -*-
"""Рядок 108: макіяж у розмові — той самий ключ і формат, що плитка. Три фрази (червона помада /
без макіяжу / нічого) → паспорт.макіяж, `сценарій.макіяж` після шва, `face_contrast.рівень_макіяжу`,
і крок контрасту біля обличчя у брифі B (K-CLR-03 «дає ще +N L*») — ДО (паспорт без поля,
плитка порожня) і ПІСЛЯ. Запуск із теки `джерела`: python3 проби/pasport_makiiazh_108.py"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, pipeline as PL, face_contrast as KC

вх = json.load(open("стенд_вх.json", encoding="utf-8"))
сц = dict(нагода="побачення", місце="ресторан_районний", година=19, темп_c=12)
ФРАЗИ = (("побачення, з червоною помадою", dict(рівень="помітний", губи="#b0203a")),
         ("побачення, без макіяжу зовсім", dict(рівень="нюд", губи=None)),
         ("побачення в ресторані о сьомій", dict(рівень="невідомо", губи=None)))
def _крок(d):
    r = json.loads(B.виклик("запити", json.dumps(d, ensure_ascii=False)))
    м = re.search(r"дає ще \+(\d+) L\*", r["B"])
    return ("+%s L*" % м.group(1)) if м else "рядка макіяжу нема"
for слова, від_моделі in ФРАЗИ:
    п = PL.паспорт_з_json(json.dumps(dict(подія=слова, нагода="побачення", макіяж=від_моделі), ensure_ascii=False), сц, слова)
    до = {k: v for k, v in п.items() if k != "макіяж"}
    print("«%s» → паспорт.макіяж=%s · рядок випадку: «%s»" % (слова, п["макіяж"], PL.паспорт_рядком(п)[:60]))
    for мітка, пасп in (("ДО", до), ("ПІСЛЯ", п)):
        d = B._застосувати_паспорт(dict(вх, сценарій=dict(сц), паспорт=пасп))
        мк = d["сценарій"].get("макіяж")
        print("  %-5s сценарій.макіяж=%-42s рівень_макіяжу=%-9s бриф B: %s"
              % (мітка, мк, KC.рівень_макіяжу(мк), _крок(d)))
# плитка й паспорт — один стан: «невідомо» від моделі не затирає плитку, рука після паспорта переважає
п1 = PL.паспорт_з_json(json.dumps(dict(макіяж=dict(рівень="невідомо"))), dict(сц, макіяж=dict(рівень="нюд")), "x")
assert п1["макіяж"] == dict(рівень="нюд"), п1["макіяж"]
п2 = PL.паспорт_з_json(json.dumps(dict(макіяж=dict(рівень="помітний"))), dict(сц, макіяж=dict(рівень="яскравий")), "x", паспорт_досі=п1)
assert п2["макіяж"] == dict(рівень="яскравий") and п2["джерело_полів"]["макіяж"] == "рука", п2
print("плитка/паспорт один стан: «невідомо» не затирає плитку; рука після паспорта переважає — так")
