# -*- coding: utf-8 -*-
"""Н2: скільки каталогу вікна палітри знімають у ДАЛЕКИХ від обличчя слотах — лише вимір, правила
не чіпано. П5 звіту Research: жорсткість спадає з відстанню (`колір_річ.SLOT_NEAR_FALLBACK`: шарф
1.0, верх 0.90, сукня 0.45, низ 0.05, взуття 0.00), а вікно палітри одне на всі слоти — тож низ і
взуття, чий колір біля обличчя майже не важить, відсіюються ще ДО суду. На живій схемі першої гілки
рангу (`стенд_вх.json`, `каталог_повний.xml`): скільки речей слота проходить його вікна, частка
знятих, вага near, скільки вікон і яку смугу L* вони дають. `python3 проби/pul_dalekі_sloty_н2.py`."""
import json, sys, collections
sys.path.insert(0, ".")
import bridge as B, палітра_специфікація as P, фід_добір as ФД, колір_річ as КР, colorspace as cs
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
СЛОТИ = ("шарф", "верх", "сукня", "верхній_шар", "сумка", "низ", "взуття")
B.виклик("запити", json.dumps(вх, ensure_ascii=False))          # той самий пул, що бачить жінка
кат = B.каталог_останнього_пакета()
F = B._features(вх)[0]
схема = (json.loads(B.виклик("палітри", json.dumps(вх, ensure_ascii=False)))["гілки"] or [{}])[0]["схема"]
вікна = [q for q in P.запит_у_фід(P.специфікація(F, схема, СЛОТИ)) if isinstance(q, dict) and q.get("L_min") is not None]
по_слоту = collections.defaultdict(list)
for r in кат:
    if r.get("слот") in СЛОТИ:
        по_слоту[r["слот"]].append(r)


def влучає(r, q):
    """Той самий засіб, що в пулі (`композитор_слоти._влучає`): зона для слова, точка для фото."""
    if r.get("вікно"):
        return ФД.частка_вікна(r["вікно"], q) > 0.0 and ФД.описує_річ(r["lab"], q, вікно=r["вікно"])
    return ФД.підходить(r["lab"], q)


print("схема першої гілки рангу: %s · вікон %d · речей каталогу %d" % (схема, len(вікна), len(кат)))
print("%-13s %6s %8s %8s %6s %6s %-11s" % ("слот", "речей", "у вікнах", "знято %", "near", "вікон", "L вікна"))
for слот in СЛОТИ:
    св = [r for r in (по_слоту.get(слот) or []) if r.get("lab")]
    вс = [q for q in вікна if not q.get("слот") or q["слот"] == слот]
    у = [r for r in св if any(влучає(r, q) for q in вс)]
    print("%-13s %6d %8d %7.1f%% %6.2f %6d %.0f..%.0f"
          % (слот, len(св), len(у), 100.0 * (1 - len(у) / max(1, len(св))),
             КР.SLOT_NEAR_FALLBACK.get(слот, 0.0), len(вс),
             min(q["L_min"] for q in вс), max(q["L_max"] for q in вс)))
    assert len(у) <= len(св)
print("pul_dalekі_sloty_н2: зелено (вимір, не гейт)")
