"""КОЛІР-МЕЖІ-ЕЛЕМЕНТА (рядок 2851): чи читачі L*/C* елемента судять колір зі слова межами вікна, а не
центром. Елемент-вікно (`outfit.елементи`) L/C/h не несе; правило дає вердикт, коли його дає все вікно,
інакше — запис «без входу» з полем `колір_не_вимір`. Друкує для трьох верхів біля обличчя — вимір айворі,
вікно «бежевий» (L 55–90, C 5–30: по обидва боки «весільного білого») і вікно «чорний» (L 5–25) — що кажуть
K-KOH-08 (вечір, біле нареченої), K-KOH-06 (діловий дрес-код, L 20–80, + фото), K-CLR-02, K-COL-01.
Запуск із джерела/: python3 проби/колір_межі_елемента.py"""
import sys; sys.path.insert(0, "."); import outfit as O, формальність as Ф, колір_світлота as КС
def вікно(слово, в): return dict(свідок="shop_word", слово=слово, вікно=в, чому="слово крамниці")
ВЕРХИ = {"айворі (вимір)": dict(hex="#f2ead8"),
         "бежевий (вікно)": dict(hex="#d8c3a5", не_вимір=вікно("бежевий", [55, 90, 5, 30, None])),
         "чорний (вікно)": dict(hex="#1a1a1a", не_вимір=вікно("чорний", [5, 25, 0, 8, None]))}
def речі(к):
    return [dict(id="верх", назва="верх", слот="верх", colors=[dict(ВЕРХИ[к], coverage=1.0)], площа=0.5),
            dict(id="низ", назва="низ", слот="низ", colors=[dict(hex="#3a3f55", coverage=1.0)], площа=0.5)]
def коротко(зн): return sorted({"%s:%s%s" % (z["правило"], z.get("сила"), " без входу" if z.get("без_входу") else "")
                                for z in зн if isinstance(z, dict) and (z.get("без_входу") or (z.get("сила_нп") or 0) > 0)})
особа = dict(доступно=True, L_шкіри=62.0, value_gap=30.0, смуга_шкіри="intermediate")
for к in ВЕРХИ:
    E = O.елементи(речі(к))
    верх = next(e for e in E if e["річ"] == "верх")
    print("%-16s L=%s C=%s" % (к, верх["L"], верх["C"]))
    print("   K-KOH-08 весілля:", коротко(Ф.нагода_палітра(E, нагода="весілля", зарезервований_колір="near_white", година=20)))
    print("   K-KOH-06 business+фото:", коротко(Ф.нагода_палітра(E, нагода="ділова", дрес_код="business_casual", фото=True)))
    print("   K-CLR-02:", коротко(КС.біля_обличчя(E, особа)), " K-COL-01:", коротко(КС.перевірка_value(E)))
