# -*- coding: utf-8 -*-
"""K-SHO-10 (маса взуття задає ВАГА ПОЛОТНА низу, не сам лише обʼєм крою).

ДО ПРАВКИ: `маса_взуття` шукала кириличні ключі `ТКАНИНА_ВАГА` у полях
`рід_тканини_слово` (три значення: «полотно» 1 030, «трикотаж» 231, None 2 403)
і `текстура` (ЛАТИНСЬКІ роди verify: denim, satin, tweed-boucle…). Вага
знаходилась на 231 речі з 3 664 (6.3 %), і всі 231 важили 0.35 — при порозі
`вага − маса > 0.3` це вимагає пари масою < 0.05, якої в таблиці нема. Отже
правило не могло спрацювати ЖОДНОГО разу.
ПІСЛЯ: 1 892 з 3 664 (51.6 %), із них 864 важчі за 0.6; рядок стоїть у
`вердикт.образи[0].знахідки`."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, accessory as АК

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["назва"]: c for c in B.каталог_останнього_пакета()}
пул = json.loads(з["руки"]["1"])["пул"]
важке = лежить = None
for сл in ("сукня", "низ"):
    for r in (пул.get(сл) or []):
        c = кат.get(r["назва"]) or {}
        сл_, вага, поле = АК._вага_полотна(c)
        if вага and вага >= 0.6 and важке is None:
            важке, лежить = r, (сл_, вага, поле)
пара = next((r for r in (пул.get("взуття") or [])
             if (кат.get(r["назва"]) or {}).get("тип") in ("човники", "балетки", "мюлі",
                                                          "босоніжки", "туфлі")), None)
print("низ: %s · полотно «%s» вага %.2f з поля «%s»" % (важке["назва"][:44], *лежить))
print("пара: %s · тип %s маса %.2f"
      % (пара["назва"][:44], кат[пара["назва"]]["тип"], АК.МАСА_ВЗУТТЯ[кат[пара["назва"]]["тип"]]))
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=json.dumps(
    {"версія": "1", "образи": [{"ід": "о1", "речі": [важке["н"], пара["н"]]}]},
    ensure_ascii=False)), ensure_ascii=False)))
зн = ((вм.get("вердикт") or {}).get("образи") or [{}])[0].get("знахідки") or []
р = next((z for z in зн if z.get("правило") == "K-SHO-10"), None)
print("K-SHO-10 у вердикті:", "НЕМА" if not р else
      "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:58]))
assert р, "правило мусить дати рядок вердикту на важкому полотні під делікатною парою"
