"""Ф-4 (звіт Research §5, «еластан»): частка еластану зі складу крамниці → поле
`еластан_%`; K-BOD-02 «облягає широку зону» від 2 % слабшає з `strong` до `soft`,
бо вікно ковзання опубліковане для ПОЛОТНА. Друкує покриття поля на каталозі й
зміну знахідок на одному тілі.
Запуск із теки `джерела`: `python3 проби/фг4_еластан.py`."""
import os, sys, collections
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as ФК, fit as ПС, силует_пропорції as СП, силует_крої as СК

кат = ФК._прочитати_каталог(feed.каталог_на_диску(), ліміт_фото=0)["каталог"]
є = [r for r in кат if r.get("еластан_%") is not None]
назв = [r for r in кат if r.get("еластан_%") is None and r.get("еластан_за_чим")]
розп = collections.Counter(r["еластан_%"] for r in є)
print("ПОКРИТТЯ ПОЛЯ `еластан_%%` на каталозі (%d речей): частка є в %d (%.1f %%); "
      "волокно назване, частки нема — %d" % (len(кат), len(є), 100.0 * len(є) / len(кат), len(назв)))
print("  частки: %s" % sorted(розп.items())[:10])
print("  від порога %g %%: %d речей · нижче: %d"
      % (СП._ЕЛАСТАН_ПОРІГ, sum(n for ч, n in розп.items() if ч >= СП._ЕЛАСТАН_ПОРІГ),
         sum(n for ч, n in розп.items() if ч < СП._ЕЛАСТАН_ПОРІГ)))

# тіло з ВИРАЗНО ширшим низом: стегна — «широка» зона, де облягання і є провалом
т = ПС.тіло(164, {"плечі": 92, "груди": 90, "талія": 72, "стегна": 104})
print("\nОДНЕ ТІЛО, ОДНА ГЕОМЕТРІЯ, РІЗНИЙ СКЛАД (K-BOD-02 по зоні «стегна»):")
for склад in (None, 1.0, 2.0, 5.0, 18.0):
    # обхват виробу 110 см на стегнах 104: припуск ПОЗИТИВНИЙ, але в смузі «облягає»
    # (нижче — інша гілка, «нижче мінімуму носіння», і в неї еластан не заведено)
    річ = dict(id="низ-1", слот="низ", тип="спідниця", крій="regular", текстура="полотно",
               верх_см=т["висоти"]["талія"], низ_см=т["висоти"]["коліно"],
               обхвати_виробу={"стегна": 110.0}, **({"еластан_%": склад} if склад else {}))
    об = СК.обгортка(т, [річ])
    зн = [з for з in СП.зонні_операції(т, об) if з["правило"] == "K-BOD-02"]
    for з in зн:
        print("  еластан %-6s → %-7s %-9s сила_нп %.2f · %s"
              % (("%g %%" % склад) if склад else "не оголошено", з["сила"], з["регістр"],
                 з["сила_нп"], (з.get("сила_нп_джерело") or "—")[:58]))
    if not зн:
        print("  еластан %-6s → знахідки нема" % (("%g %%" % склад) if склад else "не оголошено"))
