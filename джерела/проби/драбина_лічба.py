"""Наряд 3.7 (рядок 243): лічба мірила на цьому SHA. (1) Переліки, що кажуть, що означає щабель чи який він у
нагоди, — таблиці, які не виводяться з `формальність.ДРАБИНА`: щаблі й якорі `brief`, смуги дрес-кодів і місць,
профілі палітри `НАГОДА` щабля за частиною доби (`formal_evening`/`formal_day`), смуги в ключів нагод довідника.
Профілі рідкісної події понад щабель (`reserved_white*`, `mourning`) — не ошатність: наряд їх не чіпає, лише друкує.
(2) Рідкісні події в якорях і правилі ошатності промпта розмови (рядки `formality`, `_ПРАВИЛО_ОШАТНОСТІ`) і в
ключах переліків ошатності (дрес-коди, місця, вечірні й денні місця, весільні ключі, профілі щабля за добою). (3) Підйоми ошатності за годиною: вечірній підйом смуги в коді й крок угору за порою в
правилі мовної моделі. Друкує факт. Запуск із `джерела`: python3 проби/драбина_лічба.py"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import brief as Б, формальність as Ф, мовний_шар as М, паспорт_нагоди as П
РІДКІ = re.compile(r"funeral|church|wedding|premiere|gala|ceremony|white[ _]tie|black[ _]tie|tuxedo|mourning|"
                   r"похорон|церкв|весілл|прем'єр|траур", re.I)
ДР = getattr(Ф, "ДРАБИНА", None)
вивід = lambda т: ДР is not None and т == tuple((щ["смуга"][1], щ["код"]) for щ in ДР)
переліки = {"brief.ЩАБЛІ": hasattr(Б, "ЩАБЛІ") and not вивід(Б.ЩАБЛІ), "brief.ЯКОРІ_EN": hasattr(Б, "ЯКОРІ_EN"),
            "формальність.КОДИ_ДІАПАЗОНИ": hasattr(Ф, "КОДИ_ДІАПАЗОНИ"), "формальність.МІСЦЯ_ДІАПАЗОНИ": hasattr(Ф, "МІСЦЯ_ДІАПАЗОНИ"),
            "профілі НАГОДА щабля за добою": any(к in getattr(Ф, "НАГОДА", {}) for к in ("formal_evening", "formal_day")),
            "ключі паспорт_нагоди зі смугою": any("діапазон" in р for р in П.довідник()["нагоди"])}
print("переліків ошатності поза драбиною: %d %s · драбина: %s" % (sum(переліки.values()),
      [к for к, є in переліки.items() if є], "%d щаблів" % len(ДР) if ДР else "нема"))
пр = М._коди_норми()
ряд = [р for р in пр if р.startswith("- formality") or (р.startswith("  ·") and пр.index(р) <= 2)] + [М._ПРАВИЛО_ОШАТНОСТІ]
ключі = [к for т in (getattr(Ф, "КОДИ_ДІАПАЗОНИ", {}), getattr(Ф, "МІСЦЯ_ДІАПАЗОНИ", {}), getattr(Ф, "МІСЦЯ_ВЕЧІРНІ", ()),
                     getattr(Ф, "МІСЦЯ_ДЕННІ", ()), getattr(Ф, "ВЕСІЛЬНІ_КЛЮЧІ", ()))
         for к in т if РІДКІ.search(к)]
поза = [к for к in getattr(Ф, "НАГОДА", {}) if к.startswith(("reserved_white", "mourning"))]
print("рідкісних подій: у якорях і правилі ошатності %d %s · у ключах переліків ошатності %d %s" % (
      len(РІДКІ.findall(" ".join(ряд))), sorted(set(м.lower() for м in РІДКІ.findall(" ".join(ряд)))), len(ключі), ключі)
      + " · профілі рідкісної події понад щабель (не ошатність, поза нарядом): %s" % поза)
код = open("формальність.py", encoding="utf-8").read()
підйом_коду = len(re.findall(r"lo \+= _д; hi \+= _д", код))
доба_правила = len(re.findall(r"in the evening", М._ПРАВИЛО_ОШАТНОСТІ))   # «увечері там, куди ходять удень», «романтична увечері»
print("підйомів ошатності за годиною: у коді %d (`формальність.сценарій`), у правилі мовної моделі %d" % (підйом_коду, доба_правила))
