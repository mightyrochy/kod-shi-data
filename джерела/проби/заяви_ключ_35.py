"""Ключі предметів, перестановка, пропуск; старі записи П1/П3/6870 — лише діагностика форми."""
import json, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import внутрішня_мова as В, мовний_шар as М
з = [В.заява('mourning_colour_word_only', item_id=i, item=В.річ_заяви(dict(id=i, тип='сукня', колір='чорний')), source='catalogue') for i in ('а', 'б')]
р = М.розмітити_повідомлення({'картка': В.повідомлення('card_occasion', *з)})
ключі = [x['ключ'] for x in р]
номери = [з['key'] for з in json.loads(М.промпт_повідомлень(р).split('ПОВІДОМЛЕННЯ:\n')[1])]
відп = {номери[1]: 'Друга річ.', номери[0]: 'Перша річ.'}
прийнято = М.прийняти_повідомлення(р, json.dumps(відп))
assert прийнято['тексти'][ключі[0]] == 'Перша річ.' and len(set(ключі)) == 2
частка = М.прийняти_повідомлення(р, json.dumps({номери[1]: 'Друга річ.', 'чужий': 'Не звідси.'}))
assert частка['без_відповіді'] == [ключі[0]] and частка['зайві_ключі'] == ['чужий']
assert М.розмітити_повідомлення({'інше_місце': В.повідомлення('card_occasion', *з)})[0]['ключ'] == ключі[0]
print('дві речі з однаковими кодами: ключів 2; перестановка правильна; пропуск 1; чужий ключ 1')
for arg in sys.argv[1:]:
    t = pathlib.Path(arg).read_text(); запит, відповідь = t.split('── ВІДПОВІДЬ', 1)
    if '\nПОВІДОМЛЕННЯ:\n' not in запит: continue
    raw = запит.split('\nПОВІДОМЛЕННЯ:\n', 1)[1].strip()
    старі = json.loads(raw[:raw.rindex(']') + 1])
    р = М.розмітити_повідомлення({str(x['н']): {'kind': x['вид'], 'statements': x['заяви']} for x in старі})
    об = json.loads(відповідь[відповідь.index('{'):відповідь.rindex('}') + 1])
    п = М.прийняти_повідомлення(р, json.dumps(об))
    print(pathlib.Path(arg).name, 'старих номерів', len(старі), 'заяв', len(р),
          'явно без тексту', sum(x['стан'] == 'missing_text' for x in п['заяви']))
    print('Старі номери місць не є відповідями на новий виклик із номерами заяв; зміст тут не виміряно.')
