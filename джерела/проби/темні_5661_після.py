"""Рядки 6430–6434 (сім'я 5661): вибірка очима #1231 (40 з 1 227) на чинному каталозі. ФАКТ — за вердиктом очей:
скільки записів ще мають код слова виміру без тону при слові крамниці з тоном (6430, 6431, 6433), скільки двоколірних
і принтів лишились точкою (6432), і чи однотонні №1, 2, 13, 16, 30 лишились точкою. Сім'ю слова рахує проба (міра),
не продукт. Запуск: cd джерела && python3 -W ignore проби/темні_5661_після.py"""
import collections, json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as FK, verify as V
К = {r["id"]: r for r in FK._прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"]}
ВЕРДИКТИ = json.load(open(os.path.join(ТУТ, "..", "аудит", "проби", "темні_5661_вердикти.json"), encoding="utf-8"))
АХРОМ = {"чорна", "сіра", "світла нейтраль"}
def клас(в):
    п = в.get("причина") or ""
    return ("6431" if п.startswith("темний") else "6433" if п.startswith("світлий") else "6430") \
        if в["вердикт"] == "праве слово" else ("6432" if в["вердикт"].startswith("двоколірна") else в["вердикт"])
def стан(r):
    if not r.get("колір_hex_фото"):
        return "вікно слова"
    return "точка, код без тону" if V.сім_я_слова(r.get("колір_назва_фото")) in АХРОМ else "точка, код слова крамниці"
лік = collections.defaultdict(collections.Counter)
for в in ВЕРДИКТИ:
    лік[клас(в)][стан(К[в["id"]])] += 1
for к in sorted(лік):
    print("ФАКТ · %s: %s" % (к, dict(лік[к])))
print("ФАКТ · однотонні №1, 2, 13, 16, 30: %s" % ", ".join(
    "№%d %s" % (в["№"], стан(К[в["id"]])) for в in ВЕРДИКТИ if в["№"] in (1, 2, 13, 16, 30)))
print("ФАКТ · двоколірні й принт: %s" % ", ".join(
    "№%d %s" % (в["№"], стан(К[в["id"]])) for в in ВЕРДИКТИ if клас(в) == "6432"))
