"""Рядок 160(б): порожня порада моделі не має спалювати теми запрошення.

Вхід — РЕАЛЬНИЙ паспорт Ір («вигуляти собак», gemma, сід 13, сирий прогін 25.09:
`аудит/тести/сирі_2026-09-25/p4_ir_sobaky_gemma_seed13/seed13_01_паспорт_виклик_0_.txt.gz`),
де `"порада_людині": ""`. ДО правки теми ходу лягали в `поради_дані` й без слів моделі:
жінка запрошення не бачила, а наступний хід їх уже не пропонував. Проба друкує, що код
запропонував, що модель озвучила і що побачить наступний хід.
Запуск: cd джерела && python3 проби/porada_pusta_160b.py"""
import os, sys, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import паспорт_нагоди as ПН

СЦ = dict(нагода="щоденне", місце="парк", формат="просто неба", година=11)
ІР = {"подія": "прогулянка з собаками", "нагода": "щоденне", "місце": "парк",
      "формат": "просто неба", "порада_людині": "",
      "відповідь_людині": "Я зрозуміла, що ти хочеш ніжний та зручний образ у світлих тонах."}
СКАЗАНА = dict(ІР, порада_людині="Якщо хочеш, скажи, чи буде багато ходити й скільки градусів "
                                 "— і які прикраси; підберу точніше.")

теми = (ПН.порада_коду(СЦ, None, "") or {}).get("теми") or []
print("код запропонував теми: %s" % ", ".join(теми))
for ім, відп in (("порожня (Ір)", ІР), ("сказана", СКАЗАНА)):
    п = ПН.паспорт_з_json(json.dumps(відп, ensure_ascii=False), СЦ, "вигуляти собак")
    дані = list(п.get("поради_дані") or [])
    далі = (ПН.порада_коду(СЦ, dict(поради_дані=дані), "") or {}).get("теми") or []
    слід = (п.get("порада_не_озвучена") or {}).get("теми") or []
    print("порада %-13s → показано %-3s · поради_дані %-32s · наступний хід %-28s · слід про непромовлену %d"
          % (ім, "так" if п.get("порада_людині") else "нема", ", ".join(дані) or "—",
             ", ".join(далі) or "—", len(слід)))

п0 = ПН.паспорт_з_json(json.dumps(ІР, ensure_ascii=False), СЦ, "вигуляти собак")
далі0 = (ПН.порада_коду(СЦ, dict(поради_дані=list(п0.get("поради_дані") or [])), "") or {}).get("теми") or []
print("\nнепоказані теми вертаються в чергу: %s" % ("так" if set(теми) <= set(далі0) else "НІ"))
assert теми and not п0.get("порада_людині")
assert not (п0.get("поради_дані") or []), "порожня порада спалила теми: %s" % п0.get("поради_дані")
assert set(теми) <= set(далі0), "наступний хід не пропонує %s" % (set(теми) - set(далі0))
assert (п0.get("порада_не_озвучена") or {}).get("теми") == теми, "нема сліду про непромовлену пораду"
