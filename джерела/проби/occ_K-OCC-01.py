# -*- coding: utf-8 -*-
"""K-OCC-01 (траур — стан із тривалістю, не дата) — вхід нарешті доїжджає до судді.

ДВА РОЗРИВИ, ОБИДВА В ШВІ, НЕ В ЛОГІЦІ.
  1. `суд_образу.review` приймає іменований параметр `траур` і передає його в
     `формальність.нагода_палітра`, де стоїть увесь емітент. А в `сценарій.ПОЛЯ`
     такого поля не було — отже `сценарій.з_показу` клала його в `незнайомі`, і до
     судді воно не доїжджало ЖОДНОГО разу: суддя приймав, шов доставити не міг.
     Той самий клас, який цей файл уже ловив для `тон_колготи` й `заявлена_колона`.
  2. Нагода «траур» — окремий оголошений вибір у `profile.СЦЕНАРІЙ` і в показі —
     емітента не вмикала взагалі: він стояв рівно на словнику `траур`. Жінка, яка
     обрала цю нагоду й нічого більше не сказала, діставала образ БЕЗ траурного
     регістру — правило з корпусною силою `hard` мовчало на єдиній нагоді, заради
     якої написане.
ПІСЛЯ: нагода сама є оголошенням стану; тривалість не вигадується — без неї спад
не рахується, і залишок повний (стан оголошений зараз). Коли зв'язок і місяці
названі — спад працює тим самим кодом, і проба це друкує третім рядком."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, колір_образу as КО, сценарій as СЦ

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
гучні = [c for c in кат if c.get("слот") == "сукня" and c.get("lab")
         and (КО.гучність(tuple(c["lab"])).get("C") or 0) >= 40]
сук, взут = гучні[0], next(c for c in кат if c.get("слот") == "взуття")
print("«траур» у полях нагоди:", "траур" in СЦ.оголошені(),
      "· гучних суконь (C ≥ 40) у пакеті:", len(гучні))
for підпис, сц in (("робота", dict(вх["сценарій"])),
                   ("траур, тривалості не названо", dict(вх["сценарій"], нагода="траур")),
                   ("траур, близькі, 10 міс із 12",
                    dict(вх["сценарій"], нагода="траур",
                         траур={"зв'язок": "близькі", "місяців": 10}))):
    о = ((json.loads(B.виклик("від_моделі", json.dumps(
        dict(вх, сценарій=сц, ід=[сук["id"], взут["id"]]), ensure_ascii=False))
        ).get("вердикт") or {}).get("образи") or [{}])[0]
    z = next((x for x in (о.get("знахідки") or []) if x["правило"] == "K-OCC-01"), None)
    print("  %-30s → %s" % (підпис, "нема" if not z else
          "%s %.2f · %s" % (z["сила"], z["сила_нп"], z["суть"][:52])))
    if підпис.startswith("траур, тривалості"):
        assert z, "оголошена нагода «траур» мусить вмикати траурний регістр"
    if підпис.startswith("робота"):
        assert not z, "поза трауром правило мусить мовчати"
