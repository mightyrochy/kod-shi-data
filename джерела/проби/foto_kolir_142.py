# -*- coding: utf-8 -*-
"""Рядок 142 (Ф-142): кадр картки проти кольору речі — ДО (main: кадр жнив, мовчки) і ПІСЛЯ (гілка).
«Інший колір» — вимір кадру картки поза вжитком слова кольору речі (`фід_кадр_колір.узгоджений`);
«стара міра» — сім'я слова виміру кадру картки ≠ сім'ї слова кольору коду (як 23.09).
ДО — те саме рішення без файла вимірів кадрів і без заяви. Запуск: cd джерела && python3 проби/foto_kolir_142.py"""
import collections, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, фід_каталог as FK, фід_кадр_колір as ФКК, фід_збагачення as FZ, verify as V
from фід_фото import _файл_фото
кадри, зб = ФКК.читати_кадри(), FZ.читати_збагачення()
сім = lambda н: V.сім_я_слова((V.слово_крамниці(н or "") or {}).get("ім"))
def міра(кат, файли):
    по, бачені = collections.defaultdict(collections.Counter), set()
    for r in кат:
        з = зб.get(r["id"])
        if r["id"] in бачені or not FZ._збагачення_придатне(з) or r.get("чуже_фото"):
            continue
        бачені.add(r["id"]); кк, п = r.get("кадр_кольору") or {}, по[r["магазин"]]
        п["n"] += 1; п[кк.get("стан") or "—"] += 1; п["фото"] += (r.get("колір_спір") or {}).get("рішення") == "фото"
        перший = next((x.get("слово") for x in файли.get(r["id"]) or () if кк.get("стан") == "свій_кадр"
                       and x.get("файл") == _файл_фото(кк.get("кадр"))), FZ.колір_збагачення(з)[0])
        інша = сім(r["колір_назва"]) not in (None, V.сім_я_слова(перший)); п["≠"] += інша; п["межа"] += інша and not кк
    return по
після = міра(FK._прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"], кадри)
ФКК.читати_кадри, ФКК._КОНТЕКСТ = (lambda тека=None: {}), {}
до = міра(FK._прочитати_каталог(feed.каталог_на_диску(), 0)["каталог"], {})
Σ = lambda по, к: sum(c[к] for c in по.values())
print("ФАКТ · файл вимірів кадрів: %s" % ("%d речей, %d кадрів із кольором" % (len(кадри), sum(
    1 for в in кадри.values() for x in в if x.get("lab"))) if кадри else "нема — рішення бачить лише кадр жнив"))
print("ФАКТ · записів із кадром жнив %d; кадр картки іншого кольору: ДО %d мовчки → ПІСЛЯ %d із заявою; "
      "свій кадр першим %d; колір із кадрів (§5) %d" % (Σ(після, "n"), Σ(до, "інший_колір"), Σ(після, "інший_колір"),
                                                        Σ(після, "свій_кадр"), Σ(після, "фото")))
print("ФАКТ · стара міра (сім'я кадру ≠ сім'ї слова): %d → %d; з них межа слова, без заяви: %d" % (
    Σ(до, "≠"), Σ(після, "≠"), Σ(після, "межа")))
for м in ("sunwin-store.com", "wearme.ua", "maxa.ua", "cultboutique.com.ua", "feelyou.com.ua", "bella-bicchi.com"):
    д, п = до[м], після[м]
    print("   %-20s записів %4d · іншого кольору %3d мовчки → %3d із заявою · свій кадр %3d · з кадрів %2d · стара міра %3d → %3d"
          % (м, п["n"], д["інший_колір"], п["інший_колір"], п["свій_кадр"], п["фото"], д["≠"], п["≠"]))
