ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(ТУТ, ".."))
import feed, фід_слот as FS

ЦІЛІ = {  # речі з ручного огляду куратора 23.09: id → слот, у якому вони мають бути
 "ж-10663": "взуття", "ж-08906": "взуття", "ж-09188": "взуття", "ж-09457": "взуття",
 "ж-08508": "верхній_шар", "ж-08476": "верхній_шар", "ж-05124": "верхній_шар",
 "ж-08275": "верхній_шар", "ж-07677": "верхній_шар", "ж-05018": "верхній_шар",
 "ж-08390": "низ", "ж-08411": "низ", "ж-08505": "низ", "ж-08272": "низ",
 "ж-07701": "низ", "ж-04851": "низ", "ж-06101": "низ", "ж-08399": "сукня",
 "ж-08289": "верх", "ж-07576": "верх", "ж-08372": "верх", "ж-03057": "верх",
 "ж-08406": "сумка", "ж-07858": "сумка", "ж-07624": "пояс", "ж-07610": "пояс",
 "ж-07573": "прикраси", "ж-12170": None, "ж-12171": None,   # білизна слота не має
}
сирий = "/tmp/_139_сирий.xml"
if not os.path.exists(сирий):
    with gzip.open(os.path.join(ТУТ, "..", "..", "каталог_повний.xml.gz"), "rb") as вх:
        open(сирий, "wb").write(вх.read())
к = feed.читати_yml(сирий)
к = к[0] if isinstance(к, tuple) else к
рух, збої = collections.Counter(), []
for o in к:
    ог = (o.get("категорія") or "").strip().lower()
    ог = ог if ог in feed.ІМЕНА_СЛОТІВ else ((o.get("параметри") or {}).get("слот") or "").strip().lower()
    нов = feed.слот(o)
    if FS._родина_слота(ог) != FS._родина_слота(нов or ""):
        рух[(ог or "—", нов or "нема слота")] += 1
    треба = ЦІЛІ.get(o["id"].split("@")[0], "—")
    if треба != "—" and нов != треба:
        збої.append((o["id"], ог, нов, треба))
print("оферів %d · родина слота змінилась проти оголошеної: %d" % (len(к), sum(рух.values())))
for (a, b), n in рух.most_common(10):
    print("   %-14s -> %-14s %4d" % (a, b, n))
print("речі ручного огляду 23.09: %d, не в своєму слоті: %d %s" % (len(ЦІЛІ), len(збої), збої[:2]))
print("ВПАЛО %d" % len(збої))
sys.exit(1 if збої else 0)
