# -*- coding: utf-8 -*-
"""Чи ЗНАЄ код розмір запиту ДО відправки (наряд Л-2, вада 5/8 → PR #349).

Доти стелю знав лише міст: `worker.js` міряв `JSON.stringify(тіло.messages).length`
проти `СТЕЛЯ_ВХОДУ_СИМВ` і віддавав HTTP 413, а показ дізнавався про розмір уже з
відмови — рука падала цілком («Цей образ не вимальовувався»). Проба вимагає трьох
речей у показі: та сама стеля, та сама формула виміру і виклик `вмістити_запит_П`
ПЕРЕД першим `_дзвінокП` в обох функціях моделі. Друкує факт.
Запуск: cd джерела && python3 проби/шлях_розмір_вмістити.py [показ.html]"""
import os, re, sys
_К = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
показ = open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(_К, "показ.html"), encoding="utf-8").read()
worker = open(os.path.join(_К, "worker.js"), encoding="utf-8").read()

стеля_моста = int(re.search(r"СТЕЛЯ_ВХОДУ_СИМВ\s*=\s*(\d+)", worker).group(1))
м_показу = re.search(r"const СТЕЛЯ_ЗАПИТУ_П = (\d+)", показ)
стеля_коду = int(м_показу.group(1)) if м_показу else None
запас = int(re.search(r"const ЗАПАС_ЗАПИТУ_П = (\d+)", показ).group(1)) if м_показу else 0
print("стеля моста (worker.js СТЕЛЯ_ВХОДУ_СИМВ): %d симв" % стеля_моста)
print("стеля коду  (показ.html СТЕЛЯ_ЗАПИТУ_П): %s%s"
      % (стеля_коду, "" if стеля_коду else "  ← НЕМА: розмір запиту код до відправки не знає"))
формула = "JSON.stringify(п || []).length" in показ
print("та сама формула виміру, що в мості (JSON.stringify(messages).length):", формула)

def перед(ім):
    # тіло функції до її першого `_дзвінокП`: там і мусить стояти вміщення
    п = показ.index("async function %s(" % ім)
    хвіст = показ[п:показ.index("_дзвінокП", п)]
    return "await вмістити_запит_П(" in хвіст

у_моделі = {ім: перед(ім) for ім in ("модельП_блоки", "модельП")}
for ім, є in у_моделі.items():
    print("%-16s міряє запит перед відправкою: %s" % (ім, є))

сторони = dict(re.findall(r"const (СТОРОНА_ФОТО_\w+_П) = (\d+);", показ))
print("сторони фото під задачу:", сторони or "нема — фото їде тим самим боком усім задачам")
місця = {"виклик 0": "фотоДляЗапитуП(фото, СТОРОНА_ФОТО_ВИКЛИК0_П)",
         "складання рук": "СТОРОНА_ФОТО_СКЛАДАННЯ_П)",
         "опис із фото": "фотоДоСторониП(ф, СТОРОНА_ФОТО_СКЛАДАННЯ_П)",
         "приміряння · її речі": "СТОРОНА_ФОТО_ПРИМІРКИ_П)",
         "приміряння · її кадр": "СТОРОНА_ФОТО_ЛЮДИНИ_П)"}
for ім, взір in місця.items():
    print("  %-22s під задачу: %s" % (ім, взір in показ))

assert стеля_коду == стеля_моста, "стеля коду мусить бути та сама, що в мості"
assert запас > 0 and формула
assert all(у_моделі.values()), "виклик моделі, що не міряє запит, і далі падає об 413"
assert all(взір in показ for взір in місця.values())
