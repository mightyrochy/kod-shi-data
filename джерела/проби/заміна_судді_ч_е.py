# -*- coding: utf-8 -*-
"""Ч-Е Е3: судді K-OUT-44, K-OUT-28/39 (важелі), K-PAL-17, K-VAR-01, жорстке «ні» не радять заміну без суду образу.
ДО/ПІСЛЯ: виміри, сила, учасники, заяви ті самі; ремонт, ремонт_заяви і порада заміни в тексті — нема. Запуск: [SHA бази]."""
import copy, importlib, pathlib, subprocess, sys, types, warnings
warnings.simplefilter("ignore")
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
БАЗА = sys.argv[1] if len(sys.argv) > 1 else "e85e1fd646ffe3fecd99a64a9aa174a827222921"
ПОЛЕ = ("ремонт", "ремонт_заяви")
ТЕКСТ = ("суть", "чому")
пальто = dict(id="п1", слот="верхній_шар", матеріал_коди=("wool", "silk"), вовна_частка=.6, комір="шаль", рукав="реглан")
тіло = dict(профіль=[("плечі", 0, 40.), ("стегна", 0, 46.)])
річ = dict(id="ф1", назва="сумка", слот="сумка")
ч = {"сила": .3, "частки": {"L": 1, "C": 1, "тон": 1}, "роль": "акцент"}
обр = lambda і, *р: dict(ід=і, речі=list(р))


def стара(мод):
    до = types.ModuleType(мод)
    exec(subprocess.check_output(["git", "show", БАЗА + ":джерела/" + мод + ".py"]).decode("utf-8"), до.__dict__)
    return до


def ключ(з):
    return {к: v for к, v in з.items() if к not in ПОЛЕ + ТЕКСТ}


if __name__ == "__main__":
    всього = з_порадою = 0
    випадки = [("верхнє_догляд", "догляд", ([пальто],), dict(реагенти=1)),
               ("верхнє_пропорція", "плечова_вісь", ([пальто], тіло), {}),
               ("річ_з_фото", "_зн_палітри", (річ, dict(ч, стан="поза"), True), {})]
    for мод, ф, арг, кв in випадки:
        було = getattr(стара(мод), ф)(*copy.deepcopy(арг), **кв)
        стало = getattr(importlib.import_module(мод), ф)(*copy.deepcopy(арг), **кв)
        було = [було[0]] if ф == "_зн_палітри" else було
        стало = [стало[0]] if ф == "_зн_палітри" else стало
        assert len(було) == len(стало) and було, (ф, len(було), len(стало))
        for а, б in zip(було, стало):
            assert ключ(а) == ключ(б), (ф, а.get("правило"))
            assert not any(б.get(к) for к in ПОЛЕ), (ф, б["правило"])
            assert not any(сл in б.get("суть", "") + б.get("чому", "") for сл in
                           ("дай свою нейтраль", "прибрати обʼєм біля плечей", "додати обʼєму біля плечей")), б["правило"]
            всього += 1
            з_порадою += bool(а.get("ремонт"))
        print(ф, [з["правило"] for з in стало])
    # K-VAR-01: той самий вимір (слот, річ, образи), без «заміни іншою річчю того самого слота».
    образи = [dict(ід="о%d" % (і + 1), речі_н=[1, 2 + і], слоти_н={"1": "верх", str(2 + і): "низ"},
                   ід_за_номером={"1": "с1", str(2 + і): "н%d" % і}) for і in range(6)]
    стара_в, нова_в = стара("вердикт_моделі"), importlib.import_module("вердикт_моделі")
    до = стара_в.різноманітність(copy.deepcopy(образи))
    після = нова_в.різноманітність(copy.deepcopy(образи))
    зд, зп = до["знахідки"], після["знахідки"]
    assert зд and len(зд) == len(зп), (зд, зп)
    assert all(з.get("ремонт") for з in зд) and not any(з.get("ремонт") or з.get("ремонт_заяви") for з in зп), зп
    об = [dict(о, ід=о["ід"]) for о in образи]
    пд = стара_в.повтор_слота(copy.deepcopy(об), [о["ід"] for о in об])
    пп = нова_в.повтор_слота(copy.deepcopy(об), [о["ід"] for о in об])
    assert пд and len(пд) == len(пп) and all("заміни іншою" in п["чому"] for п in пд), пд
    assert not any("заміни" in п["чому"] for п in пп), пп
    assert [{к: v for к, v in п.items() if к != "чому"} for п in пд] == [{к: v for к, v in п.items() if к != "чому"} for п in пп]
    зд = зд + пд
    зп = зп + пп
    print("K-VAR-01 знахідок: ДО з порадою %d · ПІСЛЯ %d" % (len(зд), len(зп)))
    print("Знахідок без неперевіреної поради:", всього, "· мали пораду ДО:", з_порадою)
