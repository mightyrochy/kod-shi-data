"""Галерея: обидва читачі приймають лише явний придатний вимір із розкидом."""
import copy, os, sys, unittest
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import фід_кадр_колір as К, кадри_групи as Г, жнива_кадри as Ж


def головна():
    """Звірити старий Lab, вимір, інтервал і зіпсовані дані на спільному читачі."""
    в = dict(файл="b.jpg", url="https://x/b.jpg", клас="ціла_річ", слово="чорний",
             lab=[10, 0, 0], hex="#1b1b1b", колір_тип="вимір", придатна=True, розкид=0.0)
    зб = dict(фото="https://x/a.jpg", колір_основний=dict(слово="чорний", hex="#1b1b1b"))
    спір = dict(крамниця="білий")
    випадки = [({}, True), ({"колір_тип": "інтервал"}, False), ({"придатна": False}, False)]
    випадки += [({"розкид": р}, False) for р in (None, -1, True, "2", float("nan"), float("inf"))]
    випадки += [({"lab": л}, False) for л in ([1, 2], [True, 0, 0], [float("nan"), 0, 0])]
    with unittest.TestCase().assertRaises(TypeError):
        К.вимір_кадру(dict(в, lab=3))
    старий = {к: з for к, з in в.items() if к not in ("колір_тип", "придатна", "розкид")}
    assert К.вимір_кадру(старий) is None
    assert Ж.чому_мірити(старий, в["url"], 2) == "без_поверхні"
    for зміни, прийнято in випадки:
        кадр = dict(в, **зміни)
        було = copy.deepcopy(кадр)
        assert bool(К.вимір_кадру(кадр)) == прийнято
        групи = Г.групи_кадрів(зб, [кадр])
        assert bool(групи["групи"]) == прийнято
        рішення = К.після_спору(dict(id="річ"), зб, спір, dict(кадри={"річ": [кадр]}))
        assert bool(рішення["позначка"]) == прийнято
        assert repr(кадр) == repr(було)
    assert Ж.чому_мірити(в, в["url"], 2) is None
    невідомий = dict(файл="c.jpg", url="https://x/c.jpg", колір_тип="невідомо", придатна=False)
    assert Ж.чому_мірити(невідомий, невідомий["url"], 2) is None
    assert Г.групи_кадрів(зб, [старий])["без_виміру"] == ["b.jpg"]
    print("читачі галереї: %d випадків; старий Lab → у чергу; непридатний → без повтору; збій → виняток" % (len(випадки) + 1))


if __name__ == "__main__":
    головна()
