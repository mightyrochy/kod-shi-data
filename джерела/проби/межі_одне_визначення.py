"""Порівнює відмови на дроті складання, ремонту, вибору, повноти й опису без моделі.
Запуск: cd джерела; python проби/межі_одне_визначення.py
"""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import дріт_моделі as Д
import уважний_вибір as У

if __name__ == "__main__":
    випадки = [
        ([], []),
        (["підбори", "heels", "сукня", "підбори"], ["heels", "dress"]),
        ([" підбори ", "", None, "  ", "сукня"], ["heels", "dress"]),
        (["її незнайома межа", "її незнайома межа"], ["її незнайома межа"]),
    ]
    вад = 0
    for межі, очікувані in випадки:
        пакет = {"обмеження": {"жорстке_ні": межі}}
        дроти = {
            "складання": Д.пакет(пакет),
            "ремонт": Д.вердикт({}, межі=межі),
            "вибір образу": Д.вердикт({}, межі=межі, вибір=True),
            "повнота": Д.вердикт({}, межі=межі, ремонти=False),
            "оцінка речей": У._контекст(пакет, межі),
            "опис": Д.опис({"образ": {}, "межі": межі}),
        }
        for назва, дріт in дроти.items():
            отримані = дріт.get("she_refuses", [])
            збіг = отримані == очікувані
            вад += not збіг
            print("%s: %r — %s" % (назва, отримані, "збіг" if збіг else "РОЗБІЖНІСТЬ"))
    пакет = {"випадок": {"вето": {"типи": ["підбори"]}},
             "обмеження": {"жорстке_ні": ["підбори", "сукня"]}}
    for межі in (None, ["підбори", "сукня"]):
        збіг = У._контекст(пакет, межі).get("she_refuses") == Д.пакет(пакет).get("she_refuses") == ["dress"]
        вад += not збіг
        print("межа в case, явні відмови %r: %s" % (межі, "збіг" if збіг else "РОЗБІЖНІСТЬ"))
    print("розбіжностей: %d з %d" % (вад, len(випадки) * len(дроти) + 2))
    sys.exit(bool(вад))
