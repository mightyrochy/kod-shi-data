# -*- coding: utf-8 -*-
"""КОЛО-2, рядок 1610: які кольори дає кожна змінена схема на профілях стенда ж1–ж8, ДО (кут CIELAB)
і ПІСЛЯ (крок кола художника), і скільки речей пулу ДО суд схем ПІСЛЯ ремонтував би. Якір — той, що
ставить `палітра_специфікація.специфікація` без вибору жінки (очі → волосся → шкіра). Кольори дуги —
великі хроматичні речі каталогу в дузі ролі (±пів-дуги СХЕМИ) і їхнє найчастіше слово кольору.
«Ремонт» — річ дуги ДО, яку K-PAL-03 (`суд_від_моделі.схема_образу`: дуги ПІСЛЯ + запас 10°) не прийняв би.
Нейтрали+акцент, тональна й комплементарна (КОЛО-1) кроків не мають — не змінились.
Запуск із `джерела`: python3 проби/коло2_схеми.py (потрібен повний каталог)."""
import sys, pathlib, json, collections
К = pathlib.Path(__file__).resolve().parent.parent; sys.path.insert(0, str(К))
import feed as F; F.каталог_на_диску('каталог_повний.xml')
import фід_каталог as ФК, colorspace as cs, palettes as P, палітра_схеми as PS, палітра_специфікація as SP, міст_вхід as МВ
кат = [r for r in ФК._прочитати_каталог('каталог_повний.xml', 0)['каталог'] if r.get("слот") in
       {"верх", "низ", "сукня", "верхній_шар", "комплект"} and r.get("lab") and P._хроматична(tuple(r["lab"]))]
тони = [(cs.lch(tuple(r["lab"]))[2], r.get("колір_назва") or "?") for r in кат]
кут = lambda a, b: abs((a - b + 180) % 360 - 180)
ДО = {"аналогова": ((30, 15), (55, 18)), "тріада": ((120, 15), (240, 15))}
def речі(ц, пів): return [i for i, (h, _) in enumerate(тони) if кут(h, ц) <= пів]
def слово(ід): return (collections.Counter(тони[i][1] for i in ід).most_common(1) or [("—", 0)])[0][0]
print("великих хроматичних речей: %d" % len(тони))
for ж in range(1, 9):
    д = json.load(open(К.parent / ("аудит/проби/жінки/ж%d.json" % ж), encoding="utf-8"))
    Fж = МВ._features(dict(шкіра=д["skin"], волосся=д["hair"], очі=д["eyes"]))[0]
    for схема, кроки in ДО.items():
        h = SP.специфікація(Fж, схема, ["верх", "низ"])["якір_тон"]
        дуги = [д for р, д in PS.СХЕМИ[схема]["тон"](h).items() if р != "домінанта"]
        після = [((lo + ((hi - lo) % 360) / 2) % 360, ((hi - lo) % 360) / 2) for lo, hi in дуги]
        рядок, ремонт, усього = [], 0, 0
        for (зсув, пів), (ц2, пів2) in zip(кроки, після):
            а, б = речі((h + зсув) % 360, пів), речі(ц2, пів2)
            ремонт += sum(1 for i in а if all(кут(тони[i][0], ц) > п + 10 for ц, п in [(h, 15)] + після))
            усього += len(а)
            рядок.append("+%d: %3.0f° «%s» %d → %3.0f° «%s» %d" % (зсув, (h + зсув) % 360, слово(а), len(а), ц2, слово(б), len(б)))
        print("ж%d %-9s якір %3.0f° · %s · суд ремонтує %d з %d речей ДО" % (ж, схема, h, " · ".join(рядок), ремонт, усього))
