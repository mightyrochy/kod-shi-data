# -*- coding: utf-8 -*-
"""K-OUT-38 (оверсайз протікає рукавами й коміром — більше тканини ≠ тепліше).

ЧОМУ БУВ ЛИШЕ СЛІД: як і K-OUT-17, нота народжується в `теплова_функція` (dict),
а знахідкою стає в `теплові_знахідки`; батарея кликала першу без другої.
ЩО ПОКАЗУЄ ПРОБА: оверсайз-річ → рядок «оверсайз впускає вітер рукавами й
коміром — не брати цей шар ЯК тепло» стоїть у вердикті, і тепловий внесок речі
справді знижений."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
вх["сценарій"].update(темп_c=5, опади="ні")
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
к = з["кандидати"]
# річ береться з КАТАЛОГУ пакета, не лише з пулу: ознака, під яку писане правило,
# трапляється в 140 із 618 речей слота, і `перевірити_від_моделі` законно судить річ поза
# кандидатами (вона лише лягає в `поза_кандидатами`) — тим самим шляхом, яким у
# продукт заходить річ, знайдена моделлю в повному каталозі.
ціль = next(c for c in кат.values() if c.get("слот") == "верхній_шар" and (c.get("оверсайз")))
ід = [ціль["id"]] + [(к.get(сл) or [{}])[0].get("id") for сл in ("сукня", "взуття")
                     if (к.get(сл) or [])]
print("верхній шар:", ціль["назва"][:52])
print("ознака входу:", "оверсайз %s" % ціль.get("оверсайз"))
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
р = next((z for z in (о.get("знахідки") or []) if z.get("правило") == "K-OUT-38"), None)
print("K-OUT-38 у вердикті:", "НЕМА" if not р else
      "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:62]))
print("речі рядка:", (р or {}).get("речі"), "· регістр", (р or {}).get("регістр"))
import outer as OU
_тф = OU.теплова_функція([dict(ціль, слот="верхній_шар")], темп_c=5)
print("тепловий внесок із оверсайзом:", _тф.get("тепловий_внесок"))
