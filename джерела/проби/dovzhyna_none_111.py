"""Рядок 111: невідома довжина речі — «без входу», а не падіння. Міряє (1) скільки
речей одягу каталогу після `композитор_річ._у_річ` лишаються без `верх_см`/`низ_см`
по слотах обгортки (брак ДАНИХ, не коду); (2) образ сіда 3 стенда з кардиганом
`ж-04837@25union.com.ua` (`верхній_шар`): ДО падав TypeError у `силует_крої.обгортка`,
ПІСЛЯ — літера по решті речей, а річ названа полем і K-FIT-03 «питання»."""
import sys, pathlib, json, collections
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import feed as Ф, bridge as B, outfit as O, композитор_річ as КР
import силует_крої as СК, fit as ПС
вх0 = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
т = ПС.тіло(вх0["зріст"], вх0["обхвати"])
кат = Ф._прочитати_каталог(Ф.каталог_на_диску("каталог_повний.xml"))["каталог"]
всього, без = collections.Counter(), collections.Counter()
for r in кат:
    if r.get("слот") not in СК.СЛОТИ_ОБГОРТКИ: continue
    всього[r["слот"]] += 1
    без[r["слот"]] += not O.довжина_відома(КР._у_річ(r, r["слот"], тіло=т))
print("каталог (%d речей): одяг обгортки без довжини — %s"
      % (len(кат), ", ".join("%s %d з %d" % (с, без[с], всього[с])
                             for с in СК.СЛОТИ_ОБГОРТКИ if всього[с])))
# РЯДОК 215(г), 02.10.2026: пул сіда 3 тепер несе довжини з крамниці (`hem_from: shop_cm`), тож кардигана без
# довжини в ньому нема — відповідь за номерами пулу ту саму вада не діставала. Образ збираємо за id: речі
# пулу руки 1 + перший верхній шар КАТАЛОГУ без довжини (42 з 865) — рівно ту річ, про яку рядок 111.
import pal_вердикт as ПВ
вх, r, кат2, _сп = ПВ.стенд(гілка=0)
без_довж = next(c for c in кат2.values() if c.get("слот") == "верхній_шар"
                and not O.довжина_відома(КР._у_річ(c, "верхній_шар", тіло=т)))
ід = [x["id"] for с in ("верх", "низ", "взуття", "сумка") for x in (r["кандидати"].get(с) or [])[:1]] + [без_довж["id"]]
зн, в = ПВ.знахідки(вх, ід)
образ0 = (в.get("образи") or [{}])[0]
риси = образ0.get("риси") or {}
пит = [str(p.get("суть") or "") for p in ((в.get("вердикт") or {}).get("питання") or в.get("питання") or [])] \
    + [str(z.get("суть") or "") for z in зн]
print("річ без довжини: %s" % (без_довж.get("назва") or "")[:50])
print("помилка %r · літера %r · без довжини: %s" % (в.get("помилка"), риси.get("літера"), риси.get("літера_без_довжини")))
print("K-FIT-03: %s" % [s_ for s_ in пит if "не входить у контур" in s_])
assert в.get("помилка") is None and риси.get("літера_без_довжини"), "без входу не названо"
assert any("не входить у контур" in s_ for s_ in пит), "K-FIT-03 мовчить"
