"""Міряє поля без читача та лічбу доповнення на справжньому мосту; argv[1] — файл знімка."""
import json, os, runpy, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def основна():
    """Звіряє обидва ремонти, схему каталогу й обидва шляхи доповнення без моделі."""
    import вердикт_моделі as В, збирач_промптів as З, каталог_розбір as К
    import повнота_образу as П
    знімок = {}
    шлях = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else None
    for назва, дріт in (("без гейтів", {}), ("з гейтами", {"verdict": [{"gates": ["g1"]}]})):
        скелет = З.скелет(В.оголошення_ремонту(дріт))
        знімок[назва] = {"чому": "why" in скелет["outfits"][0], "знаків": len(json.dumps(скелет))}
    знімок["veto"] = sum(ш.startswith("veto.") for ш, _, _ in К.ПОЛЯ)
    знімок["veto_скелет"] = "veto" in К.скелет()
    знімок["вибір_чому"] = "why" in З.скелет(П.ВИБІР)
    for назва, файл, ключ in (("до вибору", "повнота_до_вибору_ходи.py", "вД"),
                             ("після вибору", "повнота_після_вибору_ходи.py", "вП")):
        дані = runpy.run_path(os.path.join(sys.path[0], "проби", файл))
        відповідь = {"version": "1", "fixes": дані["ходи"]}
        очікувана = П.доповнити(відповідь, дані["в2"]["вердикт"])[1]
        в = дані["міст"](ітерація=2, текст_моделі=json.dumps(відповідь),
            попередній_вердикт=дані["в2"]["вердикт"], спроба_повноти=1, до_вибору=int(назва == "до вибору"))
        знімок[назва] = {"лічба": в.get("доповнення"), "очікувана": очікувана,
            "стара_форма": дані[ключ].get("доповнення"),
            "склад": [о["речі"] for о in в["вердикт"]["образи"]]}
    print(json.dumps(знімок, ensure_ascii=False, sort_keys=True))
    if шлях:
        with open(шлях, "w", encoding="utf8") as вихід:
            json.dump(знімок, вихід, ensure_ascii=False, indent=2)


if __name__ == "__main__":
    основна()
