# -*- coding: utf-8 -*-
"""Рядок 108: порада-запрошення (з 20.09.2026 — ГРУПАМИ тем, рядок 114). На 6 сценаріях стенда —
три ходи розмови, жінка на поради НЕ відповідає: порад-реплік за хід (≤ 1, хай тем у ній до трьох),
повторів тем (0), образи збираються без відповіді (паспорт валідний, порада не в питаннях), приклади
тексту підказки для моделі (мета, макіяж, прикраси); Р-3: питань драпіровки у промпті 0 за будь-якого
стану профілю. Запуск із теки `джерела`: python3 проби/porada_108.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import pipeline as PL, протокол as ПР
from стенд_знімок import СЦЕНАРІЇ

ПРИКЛАДИ, макс_за_хід, повторів, заблоковано = {}, 0, 0, 0
for назва, сц in СЦЕНАРІЇ.items():
    сц = {k: v for k, v in сц.items() if k in PL.СХЕМА_ПАСПОРТА or k in ("опади", "вітер", "реагенти")}
    пасп, теми = None, []
    for хід, слова in enumerate(("іду, як у плитках", "ага", "ще без каблуків"), 1):
        for драп in (None, dict(метал="золото"), dict(метал="золото", білий="вершковий", нейтралі="теплі")):
            пр = PL.промпт_паспорта(сц, слова, паспорт=пасп, драп=драп)
            assert ("Які метали" not in пр and '"драп_сирий"' not in пр.split("точно за схемою:")[1]), назва
        порад = пр.count("Можеш запропонувати як ПОРАДУ"); макс_за_хід = max(макс_за_хід, порад)
        п = PL.порада_коду(сц, пасп, слова)
        for тема, підказка in (list(zip(п["теми"], п["підказки"])) if п else []):
            ПРИКЛАДИ.setdefault(тема, (назва, підказка))
            повторів += тема in теми; теми.append(тема)
        відп = dict(подія=слова, порада_людині=("Для %s я б узяла …; якщо скажеш — підлаштую точніше." % назва) if п else "",
                    відповідь_людині="Записала.")
        пасп = PL.паспорт_з_json(json.dumps(відп, ensure_ascii=False), сц, слова, паспорт_досі=пасп)
        assert bool(пасп["порада_людині"]) == bool(п) and пасп["питання_людині"] == [], пасп
        заблоковано += bool(ПР.перевірити(ПР.ВИПАДОК, dict(пасп, рядок=PL.паспорт_рядком(пасп))))
        print("%-22s хід %d порад %d теми %-26s поради_дані=%s"
              % (назва, хід, порад, ",".join((п or {}).get("теми") or ["—"]), пасп.get("поради_дані")))
print("\nпорад-реплік за хід ≤ 1: %s (макс %d) · повторів тем: %d · образи збираються без відповіді: %s (невалідних паспортів %d) · "
      "Р-3: питань драпіровки у промпті 0 за 3 станів профілю — так" % (макс_за_хід <= 1, макс_за_хід, повторів, заблоковано == 0, заблоковано))
for тема in ("мета", "макіяж", "прикраси"):
    print("підказка «%s» (%s): %s" % ((тема,) + ПРИКЛАДИ.get(тема, ("—", "не запропоновано на стенді"))))
assert макс_за_хід <= 1 and повторів == 0 and заблоковано == 0
