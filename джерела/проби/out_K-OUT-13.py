# -*- coding: utf-8 -*-
"""K-OUT-13 (висока стійка за вітру ЗАМІЩАЄ шарф — слот звільняється).

ДО ПРАВКИ: знахідка йшла у відро `команди` `outer.команди_укладки` і до вердикту
не доїжджала — те саме відро, що й K-OUT-19. Заміщення слота «шарф» ні модель,
ні жінка не бачили.
ПІСЛЯ: рядок стоїть у `вердикт.образи[0].знахідки`; умова вітру лишається
умовою — без вітру стійка нічого не заміщає, і проба це теж друкує."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
з = json.loads(B.виклик("запити", json.dumps(dict(
    вх, сценарій=dict(вх["сценарій"], темп_c=5, опади="ні", вітер=10)),
    ensure_ascii=False)))
кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
к = з["кандидати"]
взяти = lambda сл, ум: next((кат[r["id"]] for r in (к.get(сл) or [])
                             if r["id"] in кат and ум(кат[r["id"]])), None)
пальто = взяти("верхній_шар", lambda c: c.get("комір") == "стійка")
ід = [r["id"] for r in (пальто, взяти("сукня", lambda c: True),
                        взяти("взуття", lambda c: True)) if r]
print("верхній шар:", пальто["назва"][:56], "· комір", пальто.get("комір"))
for вітер in (10, None):
    сц = dict(вх["сценарій"], темп_c=5, опади="ні", вітер=вітер)
    вм = json.loads(B.виклик("від_моделі", json.dumps(
        dict(вх, сценарій=сц, ід=ід), ensure_ascii=False)))
    о = ((вм.get("вердикт") or {}).get("образи") or [{}])[0]
    р = next((z for z in (о.get("знахідки") or []) if z.get("правило") == "K-OUT-13"), None)
    print("вітер=%-4s → K-OUT-13 у вердикті: %s" % (вітер, "нема (умова вітру)" if not р
          else "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:52])))
