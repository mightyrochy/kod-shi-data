# -*- coding: utf-8 -*-
"""Рядок 151 (ручний огляд куратора 23.09.2026): «Відповісти на три питання» було глухим кутом. Екран палітри
кличе кнопкою в аркуш «Що тобі до лиця», а той без портрета не мав ЖОДНОГО питання — жінка, яка взяла кольори
через чат-помічник, відповісти не могла. Самі питання — самозвіт (K-IO-02) і портрета не потребують: КОД їх уже
приймає полем `драп` і без фото. Проба друкує, що саме міняє кожна відповідь на профілі стенда."""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge
вх = json.load(open("стенд_вх.json", encoding="utf-8"))
БАЗА = dict(шкіра=[вх["шкіра"]], волосся=вх["волосся"], очі=вх["очі"], зріст=вх["зріст"],
            обхвати=вх["обхвати"], намір="conventional", без_фото=1)

def вікно(драп):
    """Палітра на тому самому профілі — з відповідями або без них."""
    d = dict(БАЗА, **({"драп_сирий": драп} if драп else {}))
    р = json.loads(bridge.виклик("палітри", d))
    ос = р["основи"]
    return (len(ос["рекомендовані"]), len(ос["кольори"]), len(ос["інші"]),
            (р.get("осі_словами") or {}).get("hue"), str(р.get("осі_джерело") or "")[:22], ос.get("метал"))

ВАРІАНТИ = [("нічого не відповіла (як було без портрета)", None),
            ("лише метал: золото", {"метал": "золото"}),
            ("метал + білий", {"метал": "золото", "білий": "вершковий"}),
            ("усі три, теплі", {"метал": "золото", "білий": "вершковий", "нейтралі": "теплі"}),
            ("усі три, холодні", {"метал": "срібло", "білий": "оптичний", "нейтралі": "холодні"}),
            ("усі три «не бачу різниці»", {"метал": "обидва", "білий": "не бачу різниці", "нейтралі": "не бачу різниці"})]
print("профіль стенда (шкіра %s, волосся %s, очі %s), намір conventional:"
      % (вх["шкіра"], вх["волосся"][0], вх["очі"]))
print("%-42s %5s %5s %5s  %-18s %-22s %s" % ("відповіді", "рек.", "кол.", "інші", "температура", "джерело", "метал"))
ніц = None
for мітка, д in ВАРІАНТИ:
    р = вікно(д)
    if д is None: ніц = р
    print("%-42s %5d %5d %5d  %-18s %-22s %s" % (мітка, р[0], р[1], р[2], р[3], р[4], р[5]))
    assert р[3], "температура не названа взагалі"
    if д: assert р[4] == "самозвіт", "відповідь є, а джерело не самозвіт: %s" % (р[4],)
assert ніц[3] == "не стверджується" and ніц[4].startswith("утримано")
assert вікно(ВАРІАНТИ[3][1])[0] < ніц[0] and вікно(ВАРІАНТИ[4][1])[0] < ніц[0], "вікно не звузилось"
assert вікно(ВАРІАНТИ[4][1])[5] != ніц[5], "холодні відповіді не змінили металу"
print("try_pytannia_151: зелено")
