"""Звірити знахідки `аксесуари_структура` з двох знімків: склад, сила, блокує, сира й обмежена вага."""
import collections, gzip, json, sys


def main():
    """Друк таблиці «правило · ДО · ПІСЛЯ · кількість» окремо для сирої й обмеженої ваги."""
    до, після = (json.load(gzip.open(ш, 'rt', encoding='utf-8')) for ш in sys.argv[1:3])
    assert len(до) == len(після), (len(до), len(після))
    сирі, ефективні, інше = collections.Counter(), collections.Counter(), collections.Counter()
    for д, п in zip(до, після):
        assert д[:5] == п[:5], (д, п)
        if д[5] != п[5]:
            інше[д[2], 'сила', д[5], п[5]] += 1
        if д[6] != п[6]:
            інше[д[2], 'блокує', д[6], п[6]] += 1
        if д[7] != п[7]:
            сирі[д[2], д[5], д[7], п[7]] += 1
        if д[8] != п[8]:
            ефективні[д[2], д[5], д[8], п[8]] += 1
    print('знахідок', len(до), 'склад тотожний; сирих змін', sum(сирі.values()),
          'ефективних', sum(ефективні.values()), 'інших полів', dict(інше))
    for назва, т in (('сира', сирі), ('ефективна', ефективні)):
        print('\n%s вага\n| Правило | Сила | ДО | ПІСЛЯ | Кількість |\n|---|---|---|---|---|' % назва)
        for к, n in sorted(т.items(), key=str):
            print('| %s | %s | %s | %s | %d |' % (к + (n,)))


if __name__ == '__main__':
    main()
