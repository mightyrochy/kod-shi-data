"""Рядок 5825: вітрина ремонту під «нема верху й низу» — слоти, яких бракує (`missing` заяви), а не три
найбагатші слоти сім'ї (сукня, комплект, верх, низ). Пул, де низів менше, ніж суконь, комплектів і верхів;
образи — верх без низу і без обох. Друкує ФАКТ: слоти вітрини ремонту (`_слоти_повноти`, `_вітрина_ремонту`)
і `options` блокера (`вердикт_повноти`). Запуск із `джерела`:  python3 проби/повнота_слоти_верх_низ_5825.py"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import повнота_образу as ПО
скільки = dict(сукня=10, комплект=8, верх=9, низ=3, взуття=5)
пул = {с: [dict(id="%s-%d" % (с, і), н="#%d·%02d" % (і + 1, к), слот=с) for і in range(n)]
       for к, (с, n) in enumerate(скільки.items())}
блокер = lambda *бракує: dict(ід="б1", код="нема_верху_низу", суть="",
                              заяви=[dict(code="no_top_bottom_or_dress", values=dict(missing=list(бракує)))])
for назва, б, речі in (("верх без низу", блокер("bottom"), ["#1·02", "#1·04"]),
                       ("без верху й низу", блокер("top", "bottom"), ["#1·04"])):
    о = dict(ід="о1", речі=речі, структура=dict(ок=False, блокери=[б]))
    слоти, _ = ПО.слоти_повноти([о], пул)
    вітрина, _н = ПО.вітрина_ремонту([о], пул)
    в = ПО.вердикт_повноти(dict(образи=[о], вітрина=вітрина), спроба=2)
    оп = в["образи"][0]["структура"]["блокери"][0].get("варіанти") or [] if в else []
    print("%-17s · слоти повноти %s · вітрина %s · options %d (з них низів %d)" % (
        назва, sorted(слоти), sorted(вітрина), len(оп), len(set(оп) & {r["н"] for r in вітрина.get("низ", [])})))
