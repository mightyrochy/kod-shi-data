# -*- coding: utf-8 -*-
"""K-OUT-02 у ПУЛІ (рядок 1542) — `python3 проби/out_K-OUT-02_пул.py`.

Доти правило жило лише в суді: пул верхнього шару для 154 см складався з тих самих пальт, що й
для 175. Тепер довгий шар (литка, щиколотка, максі) іде після рівних — член ключа сорту за
ярусом крою (`композитор_слоти._ранг_довжини`), з тією самою силою, що в суді, і під K-OUT-01:
у морозній смузі погоди (`сценарій.МОРОЗНІ_СМУГИ`: frost, deep_frost) пропорція голосу не має — корпус:
«потрібне тепло — бери довше». `ранг_пулу` бере СМУГУ погоди (`суд_погода.придушення`), не градуси: доти
проба передавала число, `придушення` його не знало (None), і мороз не придушував — assert падав (13880).
ДРУКУЄ: силу пулу на чотирьох точках і частку довгих у пулі слота для 154 і 175 см у смузі cold."""
import sys, pathlib, json
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import feed as Ф, bridge as B, верхнє_довжина as ВД

for зр, см in ((154, "cool"), (154, "cold"), (154, "frost"), (175, "cool")):
    print("сила пулу K-OUT-02: зріст %d, смуга %s → %.2f" % (зр, см, ВД.ранг_пулу({"зріст": зр}, см)))
вх = json.load(open(_К / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml"); вх["гілка"] = 0
вх["обхвати"] = {"плечі": 90, "груди": 84, "талія": 64, "стегна": 88}
частка = {}
for зр in (154, 175):
    в = dict(вх, зріст=зр, сід=1); в["сценарій"] = dict(вх["сценарій"], смуга_погоди='cold', опади="ні")
    к = json.loads(B.виклик("запити", json.dumps(в, ensure_ascii=False)))["кандидати"].get("верхній_шар") or []
    кат = {c["id"]: c for c in B.каталог_останнього_пакета()}
    дов = sum(1 for r in к if (кат.get(r["id"]) or {}).get("довжина_рівень") in ВД.НИЖЧЕ_КОЛІНА)
    частка[зр] = дов / max(1, len(к))
    print("зріст %d, смуга cold: нижче коліна %d з %d у пулі верхнього шару" % (зр, дов, len(к)))
assert ВД.ранг_пулу({"зріст": 154}, "frost") == 0.0 and ВД.ранг_пулу({"зріст": 154}, "deep_frost") == 0.0
assert ВД.ранг_пулу({"зріст": 175}, "cool") == 0.0
# частки 154/175 лише друкуються: на каталог_повний семплер пакета (`семплер.вибрати_зі_слота`) тасує
# страти сідом і порядку добору не тримає, тож різниця часток — шум перетасування (рядок 2030)
assert ВД.ранг_пулу({"зріст": 154}, "cool") > 0 and ВД.ранг_пулу({"зріст": 154}, "cold") > 0
assert ВД.ранг_пулу({"зріст": 154}, -10) == ВД.ранг_пулу({"зріст": 154}, None) > 0   # градуси — не смуга: придушення нема
