import sys, os, pathlib, time
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
os.chdir(str(pathlib.Path(__file__).resolve().parent.parent))
import feed as F
import жнива_v2 as Ж
import жнива_збагачення as Ж1

# Ключі запису ДО поділу: вибірка 18.09 (58/58 записів) без `фото_показу` (лише показ=True)
# плюс `фото_джерело` — його додав aced0cf 19.09, у файлі до поділу (95b0102) це рядок 1183.
ДО_ПОДІЛУ = set("id url вимір впевненість заглушок запис кадр колір_крамниці магазин маска набір "
                "назва опис поля слова_крамниці слот спір тип фото_усього фото_джерело".split())
МОДЕЛЬ = "qwen3-vl-8b-instruct"
with open(Ж.КАТАЛОГ, "rb") as f:
    офери, _ = F.читати_yml(f)
речі = Ж.вибірка(офери)[:3]
фото = {o["id"]: Ж.взяти_фото(o, 6) for o in речі}
Ж.позначити_заглушки(фото, {o["id"]: o.get("магазин") for o in речі})
чистих = 0
for o in речі:
    t0 = time.time()
    з = Ж.обробити(o, фото[o["id"]], МОДЕЛЬ, показ=False)
    t1 = time.time()
    в1 = Ж1.описати(o, МОДЕЛЬ)
    чистих += "помилка" not in з and "помилка" not in в1
    print("%s  слот=%s" % (o["id"], з.get("слот")))
    print("  v2: ключів %d, як до поділу: %s (зайві %s, бракує %s) · маска.джерело=%s · помилка=%s · %.1f с"
          % (len(з), set(з) == ДО_ПОДІЛУ, sorted(set(з) - ДО_ПОДІЛУ), sorted(ДО_ПОДІЛУ - set(з)),
             (з.get("маска") or {}).get("джерело"), з.get("помилка"), t1 - t0))
    print("  v1: ключі %s · помилка=%s · %.1f с" % (sorted(в1), в1.get("помилка"), time.time() - t1))
print("без помилки в обох жнивах: %d/3" % чистих)
