# -*- coding: utf-8 -*-
"""Розбір 1/8 (вхід і сценарій): ДОВІДКА ПОКАЗУ ДОПИСУЄТЬСЯ ДО ПРОМПТА ВИКЛИКУ 0 — З ФРАЗАМИ-ПРИКЛАДАМИ.
`показ.html.додатокДоПаспортаП` кладе `ШІ_ДОВІДКА` + `станДляШі()` після промпта, який збирач
промптів (#323) складає без жодного прикладу-фрази. Друкує розміри обох частин, скільки в довідці
фраз у лапках і у скільки разів вона більша за сам промпт паспорта.
Запуск із теки `джерела`: `python3 проби/шлях_вхід_довідка_показу.py`."""
import sys, os, re, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import паспорт_нагоди as ПН

html = open("показ.html", encoding="utf-8").read()
довідка = re.search(r"const ШІ_ДОВІДКА = `(.*?)`;\n", html, re.S).group(1)
додаток = re.search(r"function додатокДоПаспортаП\(\)\{(.*?)\n\}", html, re.S).group(1)
шапка = "".join(re.findall(r"'([^']*)'", додаток.split("ДОВІДКА ПРО ЗАСТОСУНОК")[0]))
промпт = ПН.промпт_паспорта({"година": 11, "темп_c": 18}, "Збери образ під цю спідницю і чоботи для походу на концерт")
print("промпт паспорта (збирач #323):      %6d симв., лапок «» %d (це імена полів входу, не приклади)"
      % (len(промпт), len(re.findall(r"«[^»]{3,}»", промпт))))
print("шапка `додатокДоПаспортаП`:          %6d симв." % len(шапка))
print("ШІ_ДОВІДКА:                         %6d симв., лапок «» %d (слова кнопок і приклади її фраз), рядків-екранів: %d"
      % (len(довідка), len(re.findall(r"«[^»]{3,}»", довідка)), довідка.count("\n· ")))
print("СТАН ЗАРАЗ (`станДляШі`) — ще ~%d–%d симв. (рядки «· профіль/сценарій/картка/палітра/…»): %d рядків у коді"
      % (300, 900, len(re.findall(r"р\.push\(", html.split("function станДляШі")[1].split("return р.join")[0]))))
разом = len(промпт) + len(шапка) + len(довідка)
print("разом у виклик 0:                   %6d симв. — довідка це %d%% промпта" % (разом, round(100 * len(довідка) / разом)))
print("\nмісце в коді: `показ.html:4817` (`додатокДоПаспортаП`), склейка — `показ.html:5135`"
      " (`промпт = пп.промпт + '\\n\\n' + додатокДоПаспортаП()`)")
print("`збирач_промптів` забороняє приклади-фрази в оголошеннях (докстрінг «ЗАБОРОНЕНО»); довідка"
      " приносить %d лапок повз збирач, серед них приклади її речень" % len(re.findall(r"«[^»]{3,}»", довідка)))
