# -*- coding: utf-8 -*-
"""Розбір 1/8, В-10 (вхід і сценарій): ДОВІДКА ПОКАЗУ ДОПИСУВАЛАСЬ ДО ПРОМПТА ВИКЛИКУ 0 —
З ФРАЗАМИ-ПРИКЛАДАМИ. `показ.html.додатокДоПаспортаП` клав `ШІ_ДОВІДКА` + `станДляШі()` після
промпта, який збирач промптів (#323/#327) складає без жодного прикладу-фрази. Друкує розміри
обох частин, скільки в довідці фраз у лапках і у скільки разів вона більша за сам промпт.
ПІСЛЯ правки: у виклик 0 їде рівно промпт збирача; питання про застосунок має свій виклик
`помічникП`, і довідку зі станом несе саме він.
Запуск із теки `джерела`: `python3 проби/шлях_вхід_довідка_показу.py`."""
import sys, os, re
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import паспорт_нагоди as ПН

html = open("показ.html", encoding="utf-8").read()
довідка = re.search(r"const ШІ_ДОВІДКА = `(.*?)`;\n", html, re.S).group(1)
додаток = re.search(r"function додатокДоПаспортаП\(\)\{(.*?)\n\}", html, re.S)
шапка = ""
if додаток:
    шапка = "".join(re.findall(r"'([^']*)'", додаток.group(1).split("ДОВІДКА ПРО ЗАСТОСУНОК")[0]))
промпт = ПН.промпт_паспорта({"година": 11, "темп_c": 18},
                            "Збери образ під цю спідницю і чоботи для походу на концерт")
склейка = "const промпт = пп.промпт + '\\n\\n' + додатокДоПаспортаП();"
дописується = склейка in html

print("промпт паспорта (збирач):           %6d симв., лапок «» %d (це імена полів входу, не приклади)"
      % (len(промпт), len(re.findall(r"«[^»]{3,}»", промпт))))
print("шапка `додатокДоПаспортаП`:         %6d симв. (функції нема: %s)" % (len(шапка), not додаток))
print("ШІ_ДОВІДКА:                         %6d симв., лапок «» %d (слова кнопок і приклади її фраз), рядків-екранів: %d"
      % (len(довідка), len(re.findall(r"«[^»]{3,}»", довідка)), довідка.count("\n· ")))
print("СТАН ЗАРАЗ (`станДляШі`) — ще ~300–900 симв.: %d рядків у коді"
      % len(re.findall(r"р\.push\(", html.split("function станДляШі")[1].split("return р.join")[0])))
разом = len(промпт) + (len(шапка) + len(довідка) if дописується else 0)
print("разом у виклик 0:                   %6d симв. — довідка це %d%% промпта"
      % (разом, round(100 * (len(довідка) if дописується else 0) / разом)))
print("довідка дописується до виклику 0: %s" % дописується)
print("довідку зі станом несе `помічникП` (свій виклик на її питання про застосунок): %s"
      % bool(re.search(r"async function помічникП[\s\S]{0,400}ШІ_ДОВІДКА", html)))

assert not дописується, "довідка досі дописується до КОЖНОГО виклику 0 (показ.html, `паспортПоРозмовіП`)"
assert not re.search(r"function додатокДоПаспортаП|\+ додатокДоПаспортаП\(\)", html), \
    "функція `додатокДоПаспортаП` ще оголошена або ще кликана (згадка в коментарі — не вона)"
assert re.search(r"async function помічникП[\s\S]{0,400}ШІ_ДОВІДКА", html), \
    "питання про застосунок лишилось без довідки: `помічникП` її більше не несе"
print("\nВ-10: зайве у виклику 0 — нема (промпт = рівно вивід збирача, %d симв.)" % len(промпт))
