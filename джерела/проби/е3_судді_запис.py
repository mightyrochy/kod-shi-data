"""Записувач знахідок кроку ваги суддів (Е3-сила-правила): сира й обмежена вага кожної."""
import gzip, importlib, json, sys
ЦІЛІ = {('суд_річ', 'вето_покриття'): ('K-PC-08',), ('суд_річ', 'тканина_проти_крою'): ('K-MAT-01',),
        ('суд_намір', 'намір_комфорту'): ('K-PER-00',), ('перевірка_образу', 'перевірити_образ'): ('профіль',),
        ('coordination', 'координація'): ('K-COMP-01',), ('композитор_оцінка', 'оцінити'): ('K-PAL-16',),
        ('вердикт_моделі', 'вердикт_v1'): None, ('повнота_образу', 'прийняти_гейти'): None}  # None — оголошені свідомими
ЗАПИСИ, МІТКА = [], ['']


def _обхід(в, правила, out, глиб=0):
    if isinstance(в, dict) and 'сила_нп' in в and (в.get('свідомий') if правила is None else в.get('правило') in правила):
        out.append(в)
    elif isinstance(в, (dict, list, tuple)) and глиб < 6:
        for x in (в.values() if isinstance(в, dict) else в):
            _обхід(x, правила, out, глиб + 1)


def обгорнути():
    """Підмінити шість функцій у кожному модулі, що їх тримає; запис — у ЗАПИСИ."""
    from реєстр_сила import обмежити_вагу
    for (м, ф), правила in ЦІЛІ.items():
        ориг = getattr(importlib.import_module(м), ф)
        def обг(*a, _о=ориг, _п=правила, _ф=ф, **k):
            р, out = _о(*a, **k), []
            _обхід(р, _п, out)
            ЗАПИСИ.extend([МІТКА[0], _ф, з['правило'], str(з.get('суть')), з.get('речі'), з.get('сила'),
                           з.get('блокує'), з.get('сила_нп'), обмежити_вагу([dict(з)])[0].get('сила_нп')]
                          for з in out)
            return р
        for мм in list(sys.modules.values()):
            if getattr(мм, ф, None) is ориг:
                setattr(мм, ф, обг)


def записати(шлях, **дод):
    with gzip.open(шлях, 'wt', encoding='utf-8') as ф:
        json.dump(dict(записи=ЗАПИСИ, **дод), ф, ensure_ascii=False, default=str)
    print('записів', len(ЗАПИСИ), flush=True)
