# -*- coding: utf-8 -*-
"""K-IO-01 (обовʼязкові входи: профіль людини і сценарій; без обох образ не
збирається; FORCE hard). ДО ПРАВКИ: `composer.зібрати` без жодного поля сценарію
мовчки збирав пул — `_поза_сценою` без місця й нагоди не чіпала нічого, тобто у
пул ішло все від кедів до вечірньої сукні, а на картці це був образ під подію,
якої ніхто не називав. ПІСЛЯ: названий брак (`зібрано=False`, `бракує`), той самий
і в `запити` для всіх чотирьох рук. Проба міряє на стенд_вх × каталог_brief:
скільки речей пройшло б у пул без сцени (те, що було) проти стенд-нагоди, і що
саме повертають композитор і міст без сценарію."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, composer as К, сценарій as СЦ

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_brief.xml"); вх["гілка"] = 0
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
d = B._нормалізувати_вхід(B._застосувати_паспорт(dict(вх)))
F, T, _, kw = B._збірка(d)
без, _ = К._придатні(кат, None, None, T, сцен={})
зі, _ = К._придатні(кат, None, None, T, сцен=dict(вх["сценарій"]))
print("каталог %d речей · у пул без сцени пройшло б %d (типів %d) · під стенд-нагодою %s — %d"
      % (len(кат), len(без), len({r.get("тип") for r in без}), json.dumps(вх["сценарій"], ensure_ascii=False), len(зі)))
рез = К.зібрати(F, кат, тіло=T)                       # жодного поля сценарію
print("composer.зібрати без сценарію: зібрано=%s · правило %s · бракує %s\n   чому: %s"
      % (рез.get("зібрано"), рез.get("правило"), рез.get("бракує"), рез.get("чому")))
assert рез.get("зібрано") is False and рез.get("правило") == "K-IO-01"
рез2 = К.зібрати(F, кат, тіло=T, темп_c=18, опади="ні")   # погода без події — теж не сценарій
assert рез2.get("зібрано") is False, "погода без нагоди не є сценарієм"
рез3 = К.зібрати(F, кат, тіло=T, дрес_код="business_casual")
print("лише дрес_код: зібрано=%s, кандидатів %s" % (рез3.get("зібрано"), рез3.get("кандидатів")))
assert рез3.get("зібрано"), "одного визначального поля досить"
голий = {k: v for k, v in вх.items() if k not in ("сценарій", "паспорт")}   # її слова лишаються
м = json.loads(B.виклик("запити", json.dumps(голий, ensure_ascii=False)))
print("міст `запити` без сценарію: помилка=«%s» · бракує %s" % (м.get("помилка"), м.get("бракує")))
assert м.get("правило") == "K-IO-01" and "ші" not in (м.get("помилка") or "").split()
print("стенд-вхід зі сценарієм і далі збирає: пул_речей %s" % з.get("пул_речей"))
