# -*- coding: utf-8 -*-
"""Рука 2 як перевірка правила: вердикти парами «рука 1 ↔ рука 2 одного прогону» (28.09.2026).
Пара — вердикти рук 1 і 2 одного прогону. Краща рука — з вищим вердиктом («вдягну як є» >
«вдягну, якщо змінити одну річ» > «не вдягну»), за рівного — з меншим числом речей «не ця».
Група — поломка руки 2 (`поломка_руки`; для поломки «правило» ще й `правило_руки`). Однакові `склад`
(як множина) і `дібрав_код` обох карток — «образ той самий»: поломка образу не змінила, у лічбу не йде.
Стенд (профіль «Проба РВ-6», `аудит/проби/рв6_стенд.js:2004`) — не людина: його пари не рахуються.
Висновок — знаковий тест за порогами `аудит/тести/рука2_перевірка_правил_2026-09-28.md` §4.
Прогін: python3 проби/рука2_пари.py [файли чи теки вердиктів] (типово — аудит/тести/)."""
import gzip, json, os, sys
from math import comb
КОРІНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
РАНГ = {"вдягну як є": 2, "вдягну, якщо змінити одну річ": 1, "не вдягну": 0}
ключ = lambda в: (РАНГ[в["вердикт_людини"]], -len([x for x in str(в.get("замінити") or "").split("+") if x]))
образ = lambda в: (sorted(str(в.get("склад") or "").split("+")), str(в.get("дібрав_код") or ""))
хвіст = lambda n, k: sum(comb(n, i) for i in range(k, n + 1)) / 2.0 ** n   # P(≥k із n | 50/50)
шляхи = sys.argv[1:] or [os.path.join(КОРІНЬ, "аудит", "тести")]
файли = [ш for ш in шляхи if not os.path.isdir(ш)] + [   # файл — будь-яка назва; тека — лише вивантаження
    os.path.join(к, ф) for ш in шляхи if os.path.isdir(ш) for к, _, фф in os.walk(ш)
    for ф in sorted(фф) if ("verdykty" in ф or "вердикт" in ф) and ".json" in ф]
пари, стенд, групи = {}, {}, {}
for ф in файли:
    d = json.load((gzip.open if ф.endswith(".gz") else open)(ф, "rt", encoding="utf-8"))
    for п in d.get("прогони") or []:
        р = {str(в.get("рука")): в for в in п.get("вердикти") or [] if в.get("вердикт_людини") in РАНГ}
        проба = "Проба РВ-6" in str(dict(d.get("спільне") or {}, **(п.get("спільне") or {})).get("профіль"))
        if "1" in р and "2" in р:   # ключ зі складом: той самий прогін у кількох вивантаженнях — раз
            (стенд if проба else пари)[(d.get("пристрій"), п.get("прогін"), str(образ(р["1"])))] = (р["1"], р["2"])
for в1, в2 in пари.values():
    г = (в2.get("поломка_руки") or "—") + ("·" + str(в2.get("правило_руки")) if в2.get("правило_руки") else "")
    л = групи.setdefault(г, [0, 0, 0, 0])   # рука 1 краща · однаково · рука 2 краща · образ той самий
    л[3 if образ(в1) == образ(в2) else 0 if ключ(в1) > ключ(в2) else 2 if ключ(в1) < ключ(в2) else 1] += 1
print("файлів %d · пар рук 1↔2 %d · пар стенда не враховано %d" % (len(файли), len(пари), len(стенд)))
for г, (a, t, b, same) in sorted(групи.items()):
    n = a + b; p = хвіст(n, max(a, b)) if n else 1.0
    if n >= 12 and p <= 0.025: вис = "правило допомагає: лишити сильним" if a > b else "правило шкодить: переглянути"
    elif n >= 30 or (a + t + b >= 30 and t >= 2 * n): вис = "нейтральне: зробити підказкою"
    else: вис = "мало пар: з різницею %d, треба 30 (або 12+ з явною перевагою)" % n
    print("%-24s пар %3d · рука 1 краща %2d · однаково %2d · рука 2 краща %2d · образ той самий %2d · p=%.3f → %s"
          % (г, a + t + b + same, a, t, b, same, p, вис))
