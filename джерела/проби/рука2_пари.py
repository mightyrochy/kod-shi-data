# -*- coding: utf-8 -*-
"""Рука 2 як перевірка правила (28.09; Р2-2а 01.10.2026): вердикти парами «рука 1 ↔ рука 2 одного прогону».
Краща рука — вищий вердикт, за рівного — менше «не ця»; група — `поломка_руки`·`правило_руки`. Не в лічбі:
«образ той самий» (склад і `дібрав_код`) і «не діяло» (`правило_діяло` = «ні» в обох). Стенд («Проба РВ-6») пар
не дає, але частку входу рахує (`with_input` колонки `поломка`). Пороги — `аудит/тести/рука2_перевірка_правил_2026-09-28.md` §5.
Прогін: python3 проби/рука2_пари.py [файли чи теки вердиктів] (типово — аудит/тести/)."""
import gzip, json, os, re, sys; from math import comb
КОРІНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(КОРІНЬ, "джерела")); import правило_руки2 as ПР2
РАНГ = {"вдягну як є": 2, "вдягну, якщо змінити одну річ": 1, "не вдягну": 0}
ключ = lambda в: (РАНГ[в["вердикт_людини"]], -len([x for x in str(в.get("замінити") or "").split("+") if x]))
образ = lambda в: (sorted(str(в.get("склад") or "").split("+")), str(в.get("дібрав_код") or ""))
хвіст = lambda n, k: sum(comb(n, i) for i in range(k, n + 1)) / 2.0 ** n   # P(≥k із n | 50/50)
шляхи = sys.argv[1:] or [os.path.join(КОРІНЬ, "аудит", "тести")]
файли = [ш for ш in шляхи if not os.path.isdir(ш)] + [os.path.join(к, ф) for ш in шляхи if os.path.isdir(ш) for к, _, фф in os.walk(ш) for ф in sorted(фф) if ("verdykty" in ф or "вердикт" in ф) and ".json" in ф]
пари, стенд, групи, вхід = {}, {}, {}, {}
for ф in файли:  # вхід — {прогін: правила з входом}; пари — {прогін·склад: (рука 1, рука 2)}
    d = json.load((gzip.open if ф.endswith(".gz") else open)(ф, "rt", encoding="utf-8"))
    for п in d.get("прогони") or []:
        вв = {str(в.get("рука")): в for в in п.get("вердикти") or []}
        м = re.search(r"with_input=([^ ·]+)", str((вв.get("2") or {}).get("поломка") or ""))
        if м: вхід[(d.get("пристрій"), п.get("прогін"))] = set(м.group(1).split(","))
        р = {к: в for к, в in вв.items() if в.get("вердикт_людини") in РАНГ}
        проба = "Проба РВ-6" in str(dict(d.get("спільне") or {}, **(п.get("спільне") or {})).get("профіль"))
        if "1" in р and "2" in р:   # ключ зі складом: той самий прогін у кількох вивантаженнях — раз
            (стенд if проба else пари)[(d.get("пристрій"), п.get("прогін"), str(образ(р["1"])))] = (р["1"], р["2"])
for в1, в2 in пари.values():
    г = (в2.get("поломка_руки") or "—") + ("·" + str(в2.get("правило_руки")) if в2.get("правило_руки") else "")
    л = групи.setdefault(г, [0, 0, 0, 0, 0])   # рука 1 краща · однаково · рука 2 краща · образ той самий · не діяло
    л[3 if образ(в1) == образ(в2) else 4 if в1.get("правило_діяло") == в2.get("правило_діяло") == "ні" else 0 if ключ(в1) > ключ(в2) else 2 if ключ(в1) < ключ(в2) else 1] += 1
print("файлів %d · пар рук 1↔2 %d · пар стенда не враховано %d" % (len(файли), len(пари), len(стенд)))
for г, (a, t, b, same, тихо) in sorted(групи.items()):
    n = a + b; p = хвіст(n, max(a, b)) if n else 1.0
    if n >= 12 and p <= 0.025: вис = "правило допомагає: лишити сильним" if a > b else "правило шкодить: переглянути"
    elif n >= 30 or (a + t + b >= 30 and t >= 2 * n): вис = "нейтральне: зробити підказкою"
    else: вис = "мало пар: з різницею %d, треба 30 (або 12+ з явною перевагою)" % n
    print("%-24s пар %3d · рука 1 краща %2d · однаково %2d · рука 2 краща %2d · образ той самий %2d · не діяло %2d · p=%.3f → %s"
          % (г, a + t + b + same + тихо, a, t, b, same, тихо, p, вис))
if вхід: print("вхід (прогонів з with_input: %d): " % len(вхід) + " · ".join("%s %s %.0f%%" % (з["тема"], з["ід"],
              100.0 * sum(з["ід"] in v for v in вхід.values()) / len(вхід)) for з in ПР2.ПЕРЕЛІК))
