# -*- coding: utf-8 -*-
"""Проба (рядок 161): ЯКИЙ МЕТАЛ КОД ДАЄ ПРИКРАСІ Й ФУРНІТУРІ на всьому каталозі — покриття,
температура тону й згода з кольором тієї самої речі (`palettes.метал_речі`). Друкує факт, моделі не кличе.
Запуск: python3 джерела/проби/метал_тон_161.py"""
import collections, os, sys                                                   # noqa: E401
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import фід_каталог as ФК, фід_атрибути as ФА, palettes as ПЛ                  # noqa: E401,E402
ТОН = {"золото": "золото", "бронза": "золото", "латунь": "золото", "мідь": "золото",
       "рожеве_золото": "золото", "срібло": "срібло", "біле_золото": "срібло",
       "платина": "срібло", "сталь": "срібло"}
записи = ФК._прочитати_каталог(ФК.каталог_на_диску(), ліміт_фото=0)["каталог"]
c, метали = collections.Counter(), collections.Counter()
for r in записи:
    сл, м, lab = r.get("слот"), r.get("метал"), r.get("lab")
    if сл in ФА._МЕТАЛ_СЛОТИ: c["юв"] += 1
    if сл in (ФА._МЕТАЛ_СЛОТИ | ФА._МЕТАЛ_СЛОТИ_ПОЛЕ):
        c["носії"] += 1
        c["з_металом"] += 1 if м else 0
    if not м:
        continue
    метали[м] += 1
    if сл not in ФА._МЕТАЛ_СЛОТИ or lab is None:
        continue
    c["юв_з_металом_і_кольором"] += 1
    чит = ПЛ.метал_речі(tuple(lab), сл)
    if чит is None:
        c["колір_не_метал"] += 1            # камінь, емаль, тканина — тон не звірити
    elif чит != ТОН.get(м):
        c["тон_суперечить_кольору"] += 1    # ось це й є розбіжність метал↔фото/слово
    else:
        c["тон_збігся"] += 1
print("носії металу (прикраси+пояс+сумка) %d · з названим металом %d (%d %%) · ювелірних %d"
      % (c["носії"], c["з_металом"], round(100 * c["з_металом"] / (c["носії"] or 1)), c["юв"]))
print("метали: %s" % ", ".join("%s %d" % t for t in метали.most_common()))
print("ювелірних із металом і кольором %d: тон збігся %d · тон СУПЕРЕЧИТЬ %d · колір не метал %d"
      % (c["юв_з_металом_і_кольором"], c["тон_збігся"], c["тон_суперечить_кольору"], c["колір_не_метал"]))
