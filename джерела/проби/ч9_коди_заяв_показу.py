# -*- coding: utf-8 -*-
"""Рядок 206: чи існують у словнику ВСІ коди заяв і види повідомлень, які показ складає САМ.

Повідомлення внутрішньою мовою будує не лише Python: `показ.html` складає їх у JS там, де
причина відома лише сторінці (збій збирання, картка без пояснення, відмова оцінки, рядки
палітри). Код із одруківкою не падає — мовний шар мовчки кладе його в `незнайомі`, рядок
для жінки не народжується, і на екрані лишається сталий напис. Проба звіряє обидва переліки
зі словниками `внутрішня_мова.ЗАЯВИ` й `ВИДИ_ПОВІДОМЛЕНЬ` і друкує, скільки знайдено й чи є
хоч один поза словником. Запуск із теки `джерела`: `python3 проби/ч9_коди_заяв_показу.py`"""
import os, re, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ)
os.chdir(ТУТ)
import внутрішня_мова as ВМ
т = open("показ.html", encoding="utf-8").read()
т = re.sub(r"/\*.*?\*/", "", т, flags=re.S)          # коментар — не код
# `code:` і далі — або літерал, або тернар із двома літералами; змінну проба не бачить і
# чесно її не рахує (у показі таких нема: коди пишуться дослівно, саме щоб їх було видно)
ЛІТ = re.compile(r"'([a-z][a-z_0-9]{2,})'")
ВИД = re.compile(r"\bkind:\s*'([a-z_0-9]+)'")
коди = {л for м in re.finditer(r"\bcode:", т) for л in ЛІТ.findall(т[м.end():м.end() + 120].split("}")[0])}
види = set(ВИД.findall(т))
# `НАПИС_БЕЗ_ШАРУ_П` — сталі написи на ті самі види; вид без напису лишає порожнє місце
написи = set(re.findall(r"^\s{2}([a-z_0-9]+):\s*'", re.search(
    r"const НАПИС_БЕЗ_ШАРУ_П = \{.*?\n\};", т, re.S).group(0), re.M))
поза_словником = sorted(к for к in коди if к not in ВМ.ЗАЯВИ)
види_поза = sorted(в for в in види if в not in ВМ.ВИДИ_ПОВІДОМЛЕНЬ)
без_напису = sorted(в for в in види if в in ВМ.ВИДИ_ПОВІДОМЛЕНЬ and в not in написи)
print("кодів заяв, які показ складає сам: %d · ПОЗА СЛОВНИКОМ: %d %s"
      % (len(коди), len(поза_словником), поза_словником or ""))
print("видів повідомлень у показі: %d · ПОЗА СЛОВНИКОМ: %d %s"
      % (len(види), len(види_поза), види_поза or ""))
print("сталих написів `НАПИС_БЕЗ_ШАРУ_П`: %d · видів без напису: %d %s"
      % (len(написи), len(без_напису), без_напису or ""))
print("   коди: %s" % ", ".join(sorted(коди)))
