# -*- coding: utf-8 -*-
"""Рядок 121: свідоме «хай обере стилістка» для самого КОЛЬОРУ губ. ДО: поле мало два стани —
порожньо (код мовчки брав крок контрасту сталим, +10 L*) і hex; сказати «віддаю це рішення
коду» було нічим. ПІСЛЯ: третій стан лежить у тому самому `сц-губи-обрано` (другого каналу
нема), колір у паспорт як і доти не їде — K-CLR-03 не змінився, — а показ і рядок картки
вибір памʼятають. Запуск із `джерела`: python3 проби/pomada_vybir_121.py"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge, colorspace, face_contrast as FC, паспорт_нагоди as ПН

П = open("показ.html", encoding="utf-8").read()          # слова й ключі — з показу, не звідси
КЛЮЧ = re.search(r"СТИЛІСТКА_КЛЮЧ = '([^']+)'", П).group(1)
СЛОВО = re.search(r"СТИЛІСТКА_СЛОВО = '([^']+)'", П).group(1)
НАЗВАНО = re.search(r"const ГУБИ_НАЗВАНО_П = '([^']+)'", П).group(1)
р = json.loads(bridge.виклик("помади", {}))                # ендпойнт не чіпано: числа проби 116
L = 68.0
с = min(р["сходинки"], key=lambda x: abs(colorspace.hx(x["hex"])[0] - L))   # відтінок зі сходинки

def рядок(стан, hexx):        # те саме, що рядок «Макіяж» у картці сценарію
    return "Яскравий, виразний" + (", губи " + hexx if стан == НАЗВАНО
                                   else ", губи — " + СЛОВО if стан == КЛЮЧ else "")
пасп = {}
for назва, стан, hexx in [("а) не дійшла", "", None), ("б) " + СЛОВО, КЛЮЧ, None),
                          ("в) «%s»" % с["підпис"], НАЗВАНО, с["hex"])]:
    # те саме, що `зібратиВхід` складає в `сценарій.макіяж`: колір лише зі стану «названо»
    мк = ПН.макіяж_канон(dict({"рівень": "яскравий"},
                              **({"губи": hexx} if стан == НАЗВАНО else {})))
    д, джерело = FC.важіль_макіяжу(мк, L)
    пасп[стан] = json.dumps(мк, ensure_ascii=False, sort_keys=True)
    print("%-26s поле=%-12r паспорт: губи %-8s · важіль %4.1f L* (%s)\n%28sрядок: «%s»"
          % (назва, стан, мк.get("губи", "НЕМА"), д, джерело, "", рядок(стан, hexx)))
assert пасп[""] == пасп[КЛЮЧ] == '{"рівень": "яскравий"}', пасп       # у міст (б) не додає нічого
assert "губи" in пасп[НАЗВАНО] and рядок("", None) != рядок(КЛЮЧ, None)
print("(а) і (б) у ПАСПОРТІ однакові — %s; у ПОЛІ випадку різні — %r ≠ %r; рядок картки різний"
      % (пасп[""], "", КЛЮЧ))
сум = len(р["поділ"]["рекомендовані"]) + len(р["поділ"]["решта"])
print("перелік для жінки: %d відтінків ендпойнта у %d сімʼях + «свій відтінок» + «%s» · сума"
      " груп %d == уся сходинка %d" % (len(р["сходинки"]), len(р["сім_ї"]), СЛОВО, сум, len(р["сходинки"])))
assert сум == len(р["сходинки"]) and 'id="сц-губи-стилістка"' in П
assert "чипП(СТИЛІСТКА_СЛОВО" in П and "'сц-губи-обрано'" in П   # варіант і один канал на три стани
