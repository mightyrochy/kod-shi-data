"""Міряє нові жнива та відбудову журналу перед відновленням JSON-позиції."""
import tempfile
from pathlib import Path
from каталог_зависла_крамниця_жнива_проба import жнива


def main():
    """Порівнює новий прохід, втрату цілих рядків і продовження посеред сторінки."""
    помилок = 0
    for сім in ("woo", "shopify"):
        for випадок in ("новий товар", "порожній", "обрізаний", "незавершений", "обрив-порожній", "обрив-обрізаний", "позиція-порожній", "позиція-обрізаний"):
            with tempfile.TemporaryDirectory() as ж:
                обрив = випадок.startswith(("обрив-", "позиція-")) or випадок == "незавершений"
                пачка = 1 if випадок.startswith("позиція-") else None
                жнива(ж, сім, 3, стеля=2 if обрив else 300, пачка=пачка)
                файл = Path(ж) / "сирі/json.test.jsonl"
                if "порожній" in випадок:
                    файл.write_bytes(b"")
                if "обрізаний" in випадок:
                    файл.write_bytes(файл.read_bytes().splitlines(keepends=True)[0])
                кількість = 4 if випадок == "новий товар" else 3
                запити, карток, сума = жнива(ж, сім, кількість, пачка=пачка)
                очікувані = [3, 4] if пачка else [1, 2] if випадок == "новий товар" else [2] if обрив else []
                добре = запити == очікувані and карток == кількість and сума
                print(f"{сім}/{випадок}: HTTP={запити}, карток={карток}/{кількість}, повна сума={сума}, добре={добре}")
                помилок += not добре
    return int(bool(помилок))


if __name__ == "__main__":
    raise SystemExit(main())
