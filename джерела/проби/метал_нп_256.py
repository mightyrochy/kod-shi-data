# -*- coding: utf-8 -*-
"""Рядок 256: сила K-COL-06-M (метал проти драпіровки) на 20 образах «сукня+взуття+річ із металом».
Доказ слабкий (прикраси_відповідність.md: контрольованих досліджень нема, самооцінка підтону κ 0.37),
тож гілки «названий метал» і «з фото» — лише hint зі стелею `метал_нп_стеля`. Друкує факт."""
import sys, pathlib, json
_К = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_К))
import feed as Ф, bridge as B, composer as КМ, outfit as O, fit as ПС
import суд_образу as СО, colorspace as cs, дистанція as Д
вх = json.load(open(_К / "стенд_вх.json", encoding="utf-8")); вх["гілка"] = 0
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
T = ПС.тіло(float(вх["зріст"]), {k: float(v) for k, v in вх["обхвати"].items()})
F = cs.features(cs.hx(вх["шкіра"]), cs.hx(вх["волосся"][0]), cs.hx(вх["очі"]))
сук = next(c for c in кат if c.get("слот") == "сукня"); взут = next(c for c in кат if c.get("слот") == "взуття")
метал = [c for с, n in (("сережки", 10), ("кольє", 5), ("намисто", 5)) for c in [x for x in кат if x.get("метал") and x.get("слот") == с][:n]]
for підпис, драп in (("названий метал «золото»", {"метал": "золото"}), ("названий метал «срібло»", {"метал": "срібло"}),
                     ("з фото (білий/нейтралі)", {"білий": "оптичний", "нейтралі": "не бачу різниці"})):
    сили = []
    for р in метал:
        речі = [КМ._у_річ(dict(c), c["слот"], T, Д.РОЗМОВА) for c in (сук, взут, р)]
        сили += [(z["регістр"], z.get("сила_нп") or 0, z["суть"][:22]) for z in СО.метали(O.елементи(речі, дистанція=Д.РОЗМОВА), F, "uncontrolled", драп, "conventional", речі)
                 if z["правило"] == "K-COL-06-M"]
    дрейф = [x for x in сили if not x[2].startswith("метал названо")]   # без гілки «метал-деталь» (інший рядок)
    print("   лише гілки драпіровки: знахідок %d · soft %d · макс %.2f · середня %.2f" % (len(дрейф),
          sum(1 for r, _, _ in дрейф if r == "soft"), max([s for _, s, _ in дрейф] or [0]), sum(s for _, s, _ in дрейф) / (len(дрейф) or 1)))
    print("%-26s образів %d · знахідок %d · soft %d · макс сила_нп %.2f · середня %.2f"
          % (підпис, len(метал), len(сили), sum(1 for r, _, _ in сили if r == "soft"),
             max([s for _, s, _ in сили] or [0]), sum(s for _, s, _ in сили) / (len(сили) or 1)))
