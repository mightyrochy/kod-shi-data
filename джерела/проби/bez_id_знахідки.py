# -*- coding: utf-8 -*-
"""БЕКЛОГ р. 38: скільки рядків виходить БЕЗ ID корпусу на трьох стендових сценах.

Друкує факт двома ярусами, бо їх два й вони не тотожні:
  · СЛІД — те, що рахує стенд (`bridge.правила_без_ід` = `trace.без_ід`);
  · БРИФ — рядки руки B, у яких поле `правило` порожнє (там лишається діагностика,
    яка правилом і не є; її причина стоїть поруч у `чому_правило`).
"""
import json, os, sys
ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(ТУТ))
os.chdir(os.path.dirname(ТУТ))
import стенд_знімок as СТ, bridge as B, trace as СЛ          # noqa: E402

СЦЕНИ = ("офіс·18°C", "спека·парк", "дощ·ресторан·вечір")
вх0 = json.load(open("стенд_вх.json"))
слід_разом = бриф_разом = 0
for назва in СЦЕНИ:
    вх = dict(вх0, сценарій=СТ.СЦЕНАРІЇ[назва], випадок=назва)
    СЛ.почати()
    r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    if r.get("помилка"):
        print("%-22s ПОМИЛКА: %s" % (назва, r["помилка"]))
        sys.exit(1)
    слід = СЛ.без_ід()
    рядки = [p for p in ((r.get("правила_рук") or {}).get("B") or [])
             if not p.get("правило")]
    слід_разом += len(слід)
    бриф_разом += len(рядки)
    print("%-22s слід без ID: %d · рядків брифа без ID: %d" % (назва, len(слід), len(рядки)))
    for я, д in слід:
        print("    слід · %s (%s)" % (я, д))
    for p in рядки:
        print("    бриф · %s [%s] — %s" % (p["ярлик"], p["код"], p.get("чому_правило")))
print("РАЗОМ на трьох сценах: слід без ID %d · рядків брифа без ID %d"
      % (слід_разом, бриф_разом))
sys.exit(0 if слід_разом == 0 else 1)
