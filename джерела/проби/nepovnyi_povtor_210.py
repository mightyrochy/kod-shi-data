# -*- coding: utf-8 -*-
"""Рядок 210: «…; образ неповний: 3 речі…» — друга шапка посеред речення. Рядок картки
починається з «Образ неповний», а блокер `суд_від_моделі` несе ту саму шапку в собі, і зліпок
через «; » ставив дві в одне речення. Давнє, не від #301. Знімається на останньому ярусі перед
очима жінки; рядок для МОДЕЛІ лишається як був. Міряю на ВСІХ неповних образах, які код уміє
скласти.

ДО — КОНКРЕТНИЙ SHA, А НЕ РУХОМИЙ `origin/main` (рядок 149, 27.09.2026). Проба брала «ДО» з
`git show origin/main:…`, і рівно те, проти чого вона стояла, з'їло її саму: коли правку 210
злили, «ДО» стало тим самим, що «ПІСЛЯ», а далі Ч-1 (4c79c0a9) прибрала з main і `_реченням` —
проба падала `AttributeError: module 'по_до' has no attribute '_реченням'`. «ДО» тепер — 1a47cf01,
батько коміту правки 4ff6596b: єдина точка, де подвійна шапка справді була.

ПІСЛЯ — ТЕПЕРІШНЯ ФОРМА, А НЕ КОЛИШНЯ. Після Ч-1 (CLAUDE.md п.12) код рядка жінці не пише:
`_коротко_жінці` віддає ПОВІДОМЛЕННЯ кодами (`look_incomplete` — шапка, `blocker_reason` —
вільний текст корпусу), а речення складає мовна модель. Тому інваріант 210 тепер читається
так: шапка є РІВНО ОДНА — код `look_incomplete`; жоден `free_text` блокера другої шапки не несе.
Запуск із `джерела`: PYTHONPATH=. python3 проби/nepovnyi_povtor_210.py"""
import itertools, re, subprocess, sys, types; sys.path.insert(0, ".")
import повнота_образу as ПІСЛЯ, суд_від_моделі as СМ, вердикт_моделі as ВМД
БАЗА = sys.argv[1] if len(sys.argv) > 1 else "1a47cf01"
ДО = types.ModuleType("по_до"); ДО.__dict__["__name__"] = "по_до"
exec(subprocess.run(["git", "show", "%s:джерела/повнота_образу.py" % БАЗА],
                    capture_output=True, text=True, check=True).stdout, ДО.__dict__)
р = lambda і, сл, н: dict(id=і, слот=сл, тип=сл, назва=н)
КАТ = [("сукня", "Сукня"), ("верх", "Блуза"), ("низ", "Спідниця"), ("взуття", "Туфлі"),
       ("сумка", "Сумка"), ("прикраси", "Сережки"), ("верхній_шар", "Жакет")]
НАГОДИ = [dict(нагода="побачення", місце="ресторан"), dict(нагода="робота", місце="офіс"),
          dict(нагода="театр", місце="театр"), dict(нагода="весілля_гість", місце="весілля_вечірнє")]
ДВІЧІ = re.compile(r"(?i)образ\s+неповний.*образ\s+неповний")
ШАПКА = re.compile(r"(?i)^\s*образ\s+неповний\s*:")
набори = [[р(str(i), сл, н) for i, (сл, н) in enumerate(к)]
          for r in (2, 3, 4) for к in itertools.combinations(КАТ, r)]

def тексти(пвд):
    """Вільні тексти корпусу з повідомлення `card_incomplete` — те, що код віддає мовній моделі."""
    return [(з.get("values") or {}).get("reason", {}).get("free_text") or ""
            for з in ((пвд or {}).get("statements") or []) if з.get("code") == "blocker_reason"]

д = п = усього = шапок = 0
приклад = None
for сц in НАГОДИ:
    for речі in набори:
        пари = СМ.структура_образу_заяви(речі, сценарій=сц)[0]
        бл_рядки = [т for т, _ in пари]
        if not бл_рядки:
            continue
        # блокери так, як їх кладе в вердикт `блокери_структури` (код/суть/заяви) — це бачить картка
        бл = ВМД.блокери_структури(бл_рядки, речі, None, {т: з for т, з in пари if з})
        усього += 1
        рд = ДО._реченням(ДО._коротко_жінці(бл_рядки)) or ""   # КОД бази, а не відтворення тексту
        пвд = ПІСЛЯ._коротко_жінці(бл, сценарій=сц)
        шапок += sum(1 for з in ((пвд or {}).get("statements") or []) if з.get("code") == "look_incomplete")
        друга = [т for т in тексти(пвд) if ШАПКА.search(т)]
        д += bool(ДВІЧІ.search(рд)); п += bool(друга)
        if приклад is None and ДВІЧІ.search(рд):
            приклад = (рд, " + ".join(з["code"] for з in ((пвд or {}).get("statements") or [])))
print("неповних образів (усі набори 2–4 речей × 4 нагоди): %d" % усього)
print("ДО (%s): рядків із ДВОМА «образ неповний» в одному реченні: %d (%d%%)"
      % (БАЗА, д, round(д * 100.0 / усього)))
print("ПІСЛЯ: блокерів із другою шапкою у вільному тексті: %d · шапок `look_incomplete` "
      "на образ: рівно 1 у %d з %d" % (п, шапок, усього))
print("  ДО    %s" % приклад[0])
print("  ПІСЛЯ %s" % приклад[1])
print("СТЕНД ЦЬОГО НЕ ЛОВИТЬ: рв6 із SHARY=усі, сіди 3 і 7 — по 4 картки, «Образ неповний» 0 разів:")
print("  заглушка стенда завжди віддає ПОВНИЙ образ, тож жоден блокер повноти там не спрацьовує.")
sys.exit(0 if (д > 0 and п == 0 and шапок == усього) else 1)
