# -*- coding: utf-8 -*-
"""Рядок 210: «…; образ неповний: 3 речі…» — друга шапка посеред речення. Рядок
картки починається з «Образ неповний: », а блокер `суд_від_моделі` несе ту саму
шапку в собі, і зліпок через «; » ставив дві в одне речення. Давнє, не від #301.
Знімається на останньому ярусі перед очима жінки; рядок для МОДЕЛІ лишається як
був. Міряю на всіх неповних образах, які код узагалі вміє скласти: кожен набір,
де `структура_образу` дає блокер повноти. ДО — `повнота_образу` з origin/main.
Запуск із `джерела`: PYTHONPATH=. python3 проби/nepovnyi_povtor_210.py"""
import itertools, re, subprocess, sys, types; sys.path.insert(0, ".")
import повнота_образу as ПІСЛЯ, суд_від_моделі as СМ
ДО = types.ModuleType("по_до"); ДО.__dict__["__name__"] = "по_до"
exec(subprocess.run(["git","show","origin/main:джерела/повнота_образу.py"], capture_output=True, text=True).stdout, ДО.__dict__)
р = lambda і, сл, н: dict(id=і, слот=сл, тип=сл, назва=н)
КАТ = [("сукня", "Сукня"), ("верх", "Блуза"), ("низ", "Спідниця"), ("взуття", "Туфлі"),
       ("сумка", "Сумка"), ("прикраси", "Сережки"), ("верхній_шар", "Жакет")]
НАГОДИ = [dict(нагода="побачення", місце="ресторан"), dict(нагода="робота", місце="офіс"),
          dict(нагода="театр", місце="театр"), dict(нагода="весілля_гість", місце="весілля_вечірнє")]
ДВІЧІ = re.compile(r"(?i)образ\s+неповний.*образ\s+неповний")
набори = [[р(str(i), сл, н) for i, (сл, н) in enumerate(к)]
          for r in (2, 3, 4) for к in itertools.combinations(КАТ, r)]
д = п = усього = 0
приклад = None
for сц in НАГОДИ:
    for речі in набори:
        бл = СМ.структура_образу(речі, сценарій=сц)
        if not бл:
            continue
        усього += 1
        рд = ДО._реченням("Образ неповний: " + "; ".join(x for x in (ДО._без_вказівки_моделі(str(b)) for b in бл) if x))
        рп = ПІСЛЯ._реченням(ПІСЛЯ._коротко_жінці(бл)) or ""
        д += bool(ДВІЧІ.search(рд)); п += bool(ДВІЧІ.search(рп))
        if приклад is None and ДВІЧІ.search(рд):
            приклад = (рд, рп)
print("неповних образів (усі набори 2–4 речей × 4 нагоди): %d" % усього)
print("рядків із ДВОМА «образ неповний» в одному реченні: ДО %d (%d%%) → ПІСЛЯ %d"
      % (д, round(д * 100.0 / усього), п))
print("  ДО    %s" % приклад[0])
print("  ПІСЛЯ %s" % приклад[1])
print("СТЕНД ЦЬОГО НЕ ЛОВИТЬ: рв6 із SHARY=усі, сіди 3 і 7 — по 4 картки, «Образ неповний» 0 разів:")
print("  заглушка стенда завжди віддає ПОВНИЙ образ, тож жоден блокер повноти там не спрацьовує.")
