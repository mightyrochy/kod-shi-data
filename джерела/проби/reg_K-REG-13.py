# -*- coding: utf-8 -*-
"""K-REG-13 (стритвер) на живому каталозі. Запуск із теки `джерела`:
`python3 проби/reg_K-REG-13.py`.

До правки `_текст` читав лише верхні ключі речі, а сирий офер фіду має з них
`назва` й `колір_назва`: із 88 худі каталогу слово «худі» в НАЗВІ мали 30, решта
жила в `параметри["тип"]`, і шар реєстрів їх не бачив. Після — 93 речі каталогу
несуть K-REG-13 зі словом «худі», і реєстр речі доїжджає до моделі полем
`реєстр` у рядку пулу."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import feed as Ф, реєстри as РЕ, pipeline as PL

офери, _ = Ф.читати_yml(Ф.каталог_на_диску("каталог_повний.xml"))
худі = [o for o in офери if (o["параметри"].get("тип") or "").lower() == "худі"]
у_назві = [o for o in худі if "худі" in (o["назва"] or "").lower()]
print("худі в каталозі: %d · слово в назві має %d, решта — лише в `param тип`"
      % (len(худі), len(у_назві)))

лише_тип = [o for o in худі if o not in у_назві]
зразок = лише_тип[0] if лише_тип else худі[0]
в = РЕ.реєстр_речі(зразок)
print("річ: %s" % (зразок["назва"] or "")[:60])
print("  розпізнано:", в["розпізнано"], "· збіги:", в["збіги"])
print("  K-REG-13 у речі:", "стритвер" in в["бали"], "· бал %.2f" % в["бали"].get("стритвер", 0))
assert в["розпізнано"] and "стритвер" in в["бали"], в

розпізнано = sum(1 for o in худі if "стритвер" in РЕ.реєстр_речі(o)["бали"])
усього = sum(1 for o in офери if "стритвер" in РЕ.реєстр_речі(o)["бали"])
print("K-REG-13 на живому каталозі: %d речей (з них худі — %d із %d)"
      % (усього, розпізнано, len(худі)))
assert розпізнано >= len(худі), "кожне худі каталогу мусить нести стритвер"

# те саме поле, яким реєстр доїжджає до моделі: `пакет_для_моделі` кладе в річ
# `реєстр=_РЕ_кандидата(r)`, `_річ_пулу` виносить його рядком пулу.
кандидат = PL._РЕ_кандидата(зразок)
рядок = PL._річ_пулу(dict(зразок, id="п-1", реєстр=кандидат), {})
print("провідний реєстр речі для моделі:", кандидат)
print("рядок пулу:", {k: рядок[k] for k in ("назва", "реєстр") if k in рядок})
# ── ДВІ ПОЛОВИНИ, І КОЖНА В СВОЄМУ МІСЦІ (друге проходження гейта) ─────────
# РЯДОК РЕЧІ несе НАЗВУ — її читає модель, щоб виконати «домінанта плюс одна
# цитата», і ID їй для цього не потрібен. Формат рядка не змінено навмисно:
# `_пакет_у_бюджет` зрізає пул СТРАТИФІКОВАНИМ семплером (повний пул — 576 738
# символів понад бюджет 120 000), тож зайві символи в КОЖНОМУ рядку рухають
# самий зріз і викидають із пулу інші речі. Виміряно: з «стритвер [K-REG-13]»
# у рядках кандидатів 345, без них 347, і на 345 падала `reg_K-REG-05`
# («у пулі нема жодної конфліктної пари»).
# ID ПРАВИЛА несе ЛЕГЕНДА ПАКЕТА — стала мапа «назва → K-REG-NN», одна на пакет,
# ~325 символів замість ~3 800. Тринадцять K-REG-10…22 доти не називали себе у
# виході ніде, і гейт досяжності чесно звітував їх «без сліду».
assert рядок.get("реєстр") == "стритвер", рядок
_л = РЕ.ід_реєстру("стритвер")
print("легенда пакета: стритвер →", _л)
assert _л == "K-REG-13", _л
