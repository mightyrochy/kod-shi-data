# -*- coding: utf-8 -*-
"""K-SHO-08 (контраст краю важить нарівні з самим краєм).

ДО ПРАВКИ: ID стояв лише в докстрінгу `видимість_краю` й у рядку ремонту
K-SHO-07 — емітента не було. Високий виріз коштував однаково в нюді й у чорному:
судилась ФОРМА краю, його КОЛІР не рахувався ніде.
ПІСЛЯ: ΔL* пари проти сусідньої поверхні (колготки, інакше шкіра з
`outfit.контраст_особи`) міряється проти `step_min` (12.0 L*, T2 — той самий
поріг, яким `колір_образу` відрізняє два кроки світлоти). Проба друкує ОБИДВА
боки осі на тій самій формі краю: пара в тон шкіри лінії не малює, контрастна
малює, і рядок стоїть у `вердикт.образи[0].знахідки`."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = {c["назва"]: c for c in B.каталог_останнього_пакета()}
пул = json.loads(з["руки"]["1"])["пул"]
сукня = next(r for r in пул["сукня"] if (кат.get(r["назва"]) or {}).get("тип"))
L_шкіри = 75.8          # #deb295 зі стенда, `outfit.контраст_особи`
високі = [(r, кат[r["назва"]]) for r in пул["взуття"]
          if (кат.get(r["назва"]) or {}).get("виріз_стопи") == "високий" and кат[r["назва"]].get("lab")]
близька = min(високі, key=lambda x: abs(x[1]["lab"][0] - L_шкіри))
далека = max(високі, key=lambda x: abs(x[1]["lab"][0] - L_шкіри))
print("шкіра L*%.0f · сукня «%s»" % (L_шкіри, сукня["назва"][:38]))
for пара, c in (близька, далека):
    вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=json.dumps(
        {"версія": "1", "образи": [{"ід": "о1", "речі": [сукня["н"], пара["н"]]}]},
        ensure_ascii=False)), ensure_ascii=False)))
    зн = ((вм.get("вердикт") or {}).get("образи") or [{}])[0].get("знахідки") or []
    р = next((z for z in зн if z.get("правило") == "K-SHO-08"), None)
    print("виріз високий, пара L*%.0f (ΔL* %.0f) «%s»"
          % (c["lab"][0], abs(c["lab"][0] - L_шкіри), c["назва"][:40]))
    print("   K-SHO-08:", "НЕМА" if not р else
          "%s %.2f · %s" % (р["сила"], р["сила_нп"], р["суть"][:72]))
    assert р, "той самий високий виріз мусить діставати рядок по обидва боки осі"
