# -*- coding: utf-8 -*-
"""Розбір 3/8: чи кожна річ пулу їде «з повним описом» (рішення власника).

`пакет_моделі._річ_пулу` має ЗАКРИТИЙ перелік полів і порожнє поле не пише. Проба
міряє на справжньому пулі прогону власника 25.09 (розклад 4123, 337 позицій у
ПАКЕТ_V1), скільком речам якого поля НЕ дісталось, і ПРОГАНЯЄ крізь `_річ_пулу`
справжній запис її речі з фото (`річ_з_фото.запис_каталогу`): які його поля
доїжджають до моделі, а які губляться.
Прогін: cd джерела && python3 проби/шлях_пул_поля_речі.py
"""
import collections, json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import пакет_моделі as ПМ, річ_з_фото as РФ
ФАЙЛ = os.path.join(os.path.dirname(ТУТ), "аудит", "тести", "власник_2026-09-25",
                    "verdykty-0phxvk-2026-09-25-2012.json")
пул, паспорт = {}, {}
for пр in json.load(open(ФАЙЛ, encoding="utf-8"))["прогони"]:
    for в in пр["вердикти"]:
        for c in ((в.get("етапи") or {}).get("виклики") or []):
            т = (c.get("запит") or {}).get("текст") or "" if isinstance(c.get("запит"), dict) else ""
            if т.startswith("{") and c.get("крок") == "складання" and json.loads(т).get("пул"):
                пул, паспорт = json.loads(т)["пул"], пр["спільне"].get("паспорт") or {}
речі = [r for с in пул for r in пул[с]]
л = collections.Counter(k for r in речі for k in r)
print("речей у пулі ПАКЕТ_V1: %d (слотів %d)" % (len(речі), len(пул)))
for k, n in л.most_common():
    print("  %-12s є в %3d, НЕМА в %3d (%2d %%)" % (k, n, len(речі) - n,
                                                    round(100 * (len(речі) - n) / len(речі))))
# ── ЇЇ РІЧ КРІЗЬ ТОЙ САМИЙ ПОБУДОВНИК ────────────────────────────────────────
її = (паспорт.get("речі_з_фото") or [{}])[0]
запис = РФ.запис_каталогу(її)
вийшло = ПМ._річ_пулу(запис, {запис["id"]: (1, "00")})
згубл = sorted(k for k in запис if k not in вийшло and запис[k] not in (None, "", [], ()))
print("її річ %s: полів у записі %d, доїхало до моделі %d"
      % (запис["id"], len(запис), len(вийшло)))
print("  полів запису, яких модель НЕ бачить: %d — %s" % (len(згубл), ", ".join(згубл) or "—"))
print("  тканина в її речі: %r" % вийшло.get("тканина"))
без = sum(1 for r in речі if not r.get("тканина"))
print("речей пулу без поля «тканина»: %d із %d (побудовник тепер ставить «%s»)"
      % (без, len(речі), ПМ.НЕВІДОМО))
