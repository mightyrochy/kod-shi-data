# -*- coding: utf-8 -*-
"""K-SHO-07: температура вирішує, чи нога гола (мертвий параметр `темп_c`).

ДО: `видимість_краю(речі, темп_c)` діставала температуру від `перевірити`
(accessory.py:3472) і НЕ читала її — під спідницею виріз взуття важив однаково в
січні й у липні, і вісь «човник над лофером» витрачалась на невидимий край.
ПІСЛЯ: вісь вимикається там, де корпус уже сказав, що нога буде в панчішних —
`смуга_ніг(темп_c)["den"]`, та сама карта K-WEA-07, якою вже судять тип взуття
(`сезон_і_погода`) і щільність колготок (`панчішні`). Нижня межа den > 0 — це
край +18 °C, що в карті вже стоїть; власного числа не заведено. Колготи в образі
закривають ногу незалежно від градусів (вимір образу сильніший за припис)."""
import sys, pathlib, json, collections
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, accessory as A

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"], вх["гілка"] = Ф.каталог_на_диску("каталог_повний.xml"), 0
B.виклик("запити", json.dumps(вх, ensure_ascii=False))
кат = B.каталог_останнього_пакета()
_вз = [c for c in кат if c.get("слот") == "взуття"]
взуття = [c for c in _вз if c.get("виріз_стопи")]
спідниця = next(c for c in кат if c.get("тип") == "спідниця"
                and c.get("довжина_рівень") == "литка")
штани = next(c for c in кат if c.get("тип") == "штани" and c.get("довжина_рівень") == "максі")
колготи = dict(слот="колготи", назва="колготки 40 DEN", den=40)


def бал(низ, пара, t, дод=()):
    з = next((x for x in A.видимість_краю([низ, пара] + list(дод), темп_c=t)
              if x["правило"] == "K-SHO-07"), None)
    return None if not з else round(з["сила_нп"], 2)


print("пакет: %d речей, взуття %d, із них із `виріз_стопи` %d"
      % (len(кат), len(_вз), len(взуття)))
for ім, низ, дод in (("спідниця-міді", спідниця, ()), ("+ колготи 40 DEN", спідниця, (колготи,)),
                     ("штани-максі", штани, ())):
    л = collections.Counter(бал(низ, п, 25, дод) for п in взуття)
    з = collections.Counter(бал(низ, п, 5, дод) for п in взуття)
    змін = sum(1 for п in взуття if бал(низ, п, 25, дод) != бал(низ, п, 5, дод))
    print("%-16s +25 °C %s · +5 °C %s · МІНЯЮТЬ БАЛ %d (до правки 0: темп_c не читалась)"
          % (ім, dict(л), dict(з), змін))
