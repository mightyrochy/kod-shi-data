# -*- coding: utf-8 -*-
"""K-CLR-05 (на оливковому підтоні метали часто працюють обидва) — утримане рішення
вперше доїжджає, і саме правило вперше має досяжне вікно.

ДВА РОЗРИВИ, І ДРУГИЙ БУВ НЕВИДИМИЙ.
  1. УТРИМАНЕ РІШЕННЯ ГИНУЛО В ТРУБІ. Знахідка K-CLR-05 народжується з силою
     «утримано» й `сила_нп=None` (виміру нема — у цьому й суть), а
     `знахідки_вердикту` відкидає такі через `_питання_або_нуль`; `черга_на_вхід`
     бере лише регістр/силу «питання». Отже «утримано» не потрапляло НІКУДИ, і
     правило, написане проти мовчання, мовчало саме. Тепер є відро `утримано` —
     окреме від питань, бо питання каже «доміряй», а утримання «перевірено, і саме
     тому нічого не стверджую».
  2. ВІКНО ПРАВИЛА ЗНИКАЛО НА ОКРУГЛЕННІ. Умова вузька за побудовою: сира сила
     мусить лягти в [0.05, 0.125) — не нижче підлоги до гасіння й нижче після
     гасіння ×0.4. Обидва числа округлювались до сотих ДО порівняння, і 0.1225 ×
     0.4 = 0.049 ставало 0.05, тобто РІВНО підлогою. Виміряно: 43 речі з металом ×
     6 варіантів елісітації = 258 прогонів, досяжні значення сирої сили 0.0, 0.12,
     0.14, 0.17, 0.30–0.38 — у вікно лягає рівно 0.12, і саме воно гинуло.
  3. Третій вхід, який правило множить: `near`. Доти `composer._у_річ` ставив його
     двійкою (0.9 верху, 0.1 усьому іншому) і таблиця `колір_образу.
     SLOT_NEAR_FALLBACK` на живому шляху не спрацьовувала жодного разу."""
import sys, pathlib, json, collections
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B, composer as КМ, outfit as O, fit as ПС
import суд_образу as СО, colorspace as cs, колір_образу as КО

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
T = ПС.тіло(float(вх["зріст"]), {k: float(v) for k, v in вх["обхвати"].items()})
F = cs.features(cs.hx(вх["шкіра"]), cs.hx(вх["волосся"][0]), cs.hx(вх["очі"]))
сук = next(c for c in кат if c.get("слот") == "сукня")
взут = next(c for c in кат if c.get("слот") == "взуття")
метал = [c for c in кат if c.get("метал")]
драпи = [{"білий": "вершковий"}, {"білий": "оптичний"}, {"нейтралі": "теплі"},
         {"нейтралі": "холодні"}, {"білий": "вершковий", "нейтралі": "не бачу різниці"},
         {"білий": "оптичний", "нейтралі": "не бачу різниці"}]
влучань, зразок = 0, None
for річ in метал:
    for драп in драпи:
        речі = [КМ._у_річ(dict(c), c["слот"], T) for c in (сук, взут, річ)]
        for z in СО.метали(O.елементи(речі), F, "uncontrolled", драп, "conventional", речі):
            if z["правило"] == "K-CLR-05":
                влучань += 1
                зразок = зразок or (річ, драп, z)
print("підтон людини стенда: %s · речей із металом у пакеті %d"
      % (F["шкіра"].get("undertone"), len(метал)))
print("K-CLR-05 спрацьовує у %d прогонах із %d (43 речі × 6 елісітацій)"
      % (влучань, len(метал) * len(драпи)))
річ, драп, z = зразок
print("   %s «%s» + елісітація %s → %s" % (річ["слот"], річ["назва"][:26], драп, z["суть"][:56]))
# near з таблиці, а не з двійки
_р = КМ._у_річ(dict(річ), річ["слот"], T)
print("near слота «%s»: таблиця %.2f · у речі %.2f (доти двійка давала 0.10)"
      % (річ["слот"], КО.SLOT_NEAR_FALLBACK.get(річ["слот"], 0.2), _р["near"]))
assert влучань >= 1, "вікно правила мусить бути досяжним хоч раз на живому каталозі"
# утримане рішення доїжджає окремим відром
ід = [next(c for c in кат if c.get("слот") == сл)["id"] for сл in ("сукня", "взуття", "сумка")]
вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False)))
ут = вм.get("утримано") or []
print("відро «утримано» на живому шляху: %d рядків — %s"
      % (len(ут), "; ".join("%s: %s" % (x["правило"], x["суть"][:38]) for x in ут)))
assert ут, "утримане рішення мусить виходити, а не гинути між відрами"
