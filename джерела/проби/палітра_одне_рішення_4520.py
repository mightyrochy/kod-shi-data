# -*- coding: utf-8 -*-
"""Рядок 4520: схема й основа на екрані «Палітра» ≠ ті, з яких зібрано образи. Вхід — записані прогони
ЖИВІ-19…21 (гілки `claude/zhyvi-19/20/21`, `аудит/живі_N/*/*/`: `лог.txt` і `VIDPOVIDI/*вибір_палітри*`).
ДО — як записано: екран (рядок «П-7 вибір стилістки на екрані») проти діагнозу прогону («palette · choice»).
ПІСЛЯ — відтворення записаних відповідей: «Зібрати образи» бере рішення екрана, коли промпт той самий
(`за_промптом`) або вона нічого не міняла після екрана (`закріпитиПоказануП`; стенд між 1б і збиранням
не торкається нічого). Запуск із `джерела`: python3 проби/палітра_одне_рішення_4520.py"""
import re, subprocess
def git(*а): return subprocess.run(["git", "-c", "core.quotepath=false", *а], capture_output=True, text=True).stdout
ЕКРАН = re.compile(r"вибір стилістки на екрані: .*?Основа — ([^\s(·]+)[^·]*· схема — ([^(·]+?) \(")
ДІАГ = re.compile(r"П-7 діагноз вибору палітри: \[\"palette · choice · scheme=([^ ]+) .*? base=([^ ]+) ")
до = після_промпт = після = сцен = 0
for н in (19, 20, 21):
    гл = "origin/claude/zhyvi-%d" % н
    файли = git("ls-tree", "-r", "--name-only", "--full-tree", гл, "аудит/живі_%d/" % н).splitlines()
    for тека in sorted({ф.split("/VIDPOVIDI/")[0] for ф in файли if "вибір_палітри" in ф}):
        лог = git("show", "%s:%s/лог.txt" % (гл, тека))
        е, д = ЕКРАН.search(лог), ДІАГ.search(лог)
        if not (е and д):
            continue
        виклики = sorted(ф for ф in файли if ф.startswith(тека + "/VIDPOVIDI/") and "вибір_палітри" in ф)
        промпти = [git("show", гл + ":" + ф).split("── ВІДПОВІДЬ")[0] for ф in виклики[:2]]
        той_самий = len(промпти) == 2 and промпти[0] == промпти[1]
        різні = (е.group(2).strip(), е.group(1)) != (д.group(1), д.group(2))
        сцен += 1; до += різні; після_промпт += різні and not той_самий
        print("%-48s екран %s/%s · образи %s/%s · промпт %s · ДО %s · ПІСЛЯ збіг" % (
            тека[6:], е.group(2).strip(), е.group(1), д.group(1), д.group(2),
            "той самий" if той_самий else "інший", "≠" if різні else "="))
if not сцен:
    raise SystemExit("нема записаних прогонів: git fetch origin claude/zhyvi-19 claude/zhyvi-20 claude/zhyvi-21")
print("сцен із вибором стилістки: %d · екран ≠ образи: ДО %d/%d · ПІСЛЯ лише за промптом %d/%d · ПІСЛЯ %d/%d"
      % (сцен, до, сцен, після_промпт, сцен, після, сцен))
