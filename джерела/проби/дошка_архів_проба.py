# -*- coding: utf-8 -*-
"""Перевіряє унікальність номера, правку в архіві й повернення в робочу дошку."""
from pathlib import Path
import sys
from tempfile import TemporaryDirectory

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'прилади'))
import згорнути_дошку as згортання
from дошка_поля import читати_сховище, шляхи_дошки


def рядок(номер, стан):
    """Готує старий рядок, для якого додаткові поля не обов'язкові."""
    return f'| {номер} | джерело | вага | **{стан}** | доказ | файл | команда |\n'


if __name__ == '__main__':
    with TemporaryDirectory() as тека:
        згортання.КОРІНЬ, згортання.ТЕКА = тека, str(Path(тека) / 'дошка')
        згортання.КОРЕНІ, згортання.ДОШКА = str(Path(тека) / 'корені'), str(Path(тека) / 'БЕКЛОГ.md')
        шляхи = шляхи_дошки(згортання.ДОШКА)
        робоча, закрито, застаріле = шляхи
        Path(згортання.ТЕКА).mkdir()
        закрито.parent.mkdir()
        робоча.write_text(рядок(1, 'ВІДКРИТО'), encoding='utf-8')
        закрито.write_text(рядок(2, 'ЗАКРИТО'), encoding='utf-8')
        застаріле.write_text(рядок(3, 'ВІДКРИТО') + '- **3.** названих файлів нема: `x.py`\n', encoding='utf-8')
        фрагмент = Path(згортання.ТЕКА) / 'проба.md'
        фрагмент.write_text(рядок(2, 'ВІДКРИТО'), encoding='utf-8')
        assert any('номер 2 зайнятий' in п for п in згортання.згорнути(True)[1])
        фрагмент.write_text('стан 2: **ЗАКРИТО #5**\nзаміна ' + рядок(3, 'ВІДКРИТО').replace('доказ', 'новий доказ'), encoding='utf-8')
        assert not згортання.згорнути()[1] and '#5' in закрито.read_text() and 'новий доказ' in застаріле.read_text()
        фрагмент.write_text('стан 1: **ЗАКРИТО**\nстан! 2: **ВІДКРИТО**\nстан! 3: **ВІДКРИТО**\n', encoding='utf-8')
        assert not згортання.згорнути(True)[1] and not згортання.згорнути()[1]
        _, де, _, вади = читати_сховище(шляхи)
        assert not вади and де == {'1': закрито, '2': робоча, '3': робоча}
        assert 'названих файлів нема' not in застаріле.read_text()
        застаріле.write_text(рядок(1, 'ВІДКРИТО'), encoding='utf-8')
        assert any('номер 1 повторено' in п for п in згортання.згорнути(True)[1])
    print('Архів: дублікати відхилено; правки на місці, закриття й повернення з обох архівів пройшли.')
