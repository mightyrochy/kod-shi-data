import feed as Ф, re
вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["каталог"] = Ф.каталог_на_диску("каталог_brief.xml")
def смугастих(п_):
    r = json.loads(B.виклик("запити", json.dumps(dict(вх, **п_), ensure_ascii=False)))
    речі = [x for с in r["кандидати"].values() for x in с]
    return sum(1 for x in речі if re.search(r"полос|смуг|смуж", str(x.get("назва") or ""), re.I)), len(речі)
б, з = смугастих({}), смугастих(dict(паспорт=dict(вето=dict(принти=["смужка"]))))
