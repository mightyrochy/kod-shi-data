пр = пп["промпт"]
print("промпт: розмова %s · паспорт досі %s · ключі нагод %s · ключі місць %s · символів %d"
      % ("Розмова досі:" in пр, "Паспорт досі" in пр, "побачення — Побачення" in пр,
         "ресторан_районний — Заклад" in пр, len(пр)))
відп = json.dumps(dict(подія="побачення в ресторані", нагода="побачення", місце="ресторан_районний", година=19,
                       опади="так", вето=dict(типи=["підбори"]), питання_людині=["Наскільки ошатно?"],
                       відповідь_людині="Побачення в ресторані о 19:00, дощ, без підборів."), ensure_ascii=False)
п = json.loads(B.виклик("паспорт", json.dumps(dict(сценарій=сц, вимоги="", json_моделі=відп),
                                                ensure_ascii=False)))["паспорт"]
print("паспорт: нагода %s · місце %s · година %s · опади %s · вето типи %s · питань %d · відповідь «%s»"
      % (п["нагода"], п["місце"], п["година"], п["опади"], п["вето"]["типи"], len(п["питання_людині"]),
         п["відповідь_людині"][:40]))
assert п["нагода"] == "побачення" and п["місце"] == "ресторан_районний", п
д = B._застосувати_паспорт(dict(сценарій=dict(сц), паспорт=п))
print("сценарій після паспорта: нагода %s · місце %s · випадок «%s»"
      % (д["сценарій"]["нагода"], д["сценарій"]["місце"], д["випадок"][:60]))
п2 = PL.паспорт_з_json(json.dumps(dict(подія="вечеря", місце="кав'ярня на даху"), ensure_ascii=False), сц, "")
