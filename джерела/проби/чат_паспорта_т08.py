сц = dict(нагода="робота", місце="офіс_креативний", година=11, темп_c=18)
історія = [dict(хто="людина", текст="побачення в ресторані, дощ, без підборів"),
           dict(хто="ші", текст="Зрозуміла: побачення в закладі. О котрій?"),
           dict(хто="людина", текст="о сьомій вечора")]
