import feed as Ф, re
вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["каталог"] = Ф.каталог_на_диску("каталог_brief.xml")
def смугастих(п_):
    r = json.loads(B.виклик("запити", json.dumps(dict(вх, **п_), ensure_ascii=False)))
    речі = [x for с in r["кандидати"].values() for x in с]
    return sum(1 for x in речі if re.search(r"полос|смуг|смуж", str(x.get("назва") or ""), re.I)), len(речі)
# ФІЛЬТР МІРЯЄТЬСЯ НА ЇЇ СЛОВАХ, А НЕ НА ГОЛОМУ ВЕТО МОДЕЛІ (24.09). Голе
# `вето.принти` без її слів рядок 156 гасить навмисне, тож воно нічого не знімає
# з пулу — це не втрата, а те саме правило. Важить інше: чи ЗНІМАЄ фільтр
# смугасті речі, коли жінка відмовилась — своєю формою слова теж («смугастий»).
б = смугастих({})
г = смугастих(dict(паспорт=dict(вето=dict(принти=["смужка"]))))
сл = смугастих(dict(паспорт=dict(вето=dict(принти=["смужка"]), слова="не хочу смужку")))
кр = смугастих(dict(паспорт=dict(вето=dict(принти=["смужка"]), слова="смугастий одяг мені не йде")))
print("речей «в полоску/смугаст» серед кандидатів: без вето %d із %d · вето без її слів %d із %d"
      % (б + г))
print("  · вето + «не хочу смужку» %d із %d · вето + «смугастий одяг мені не йде» %d із %d" % (сл + кр))
assert сл[0] == 0 and кр[0] == 0, (сл, кр)

