# -*- coding: utf-8 -*-
"""М-6, рядок 175: КОЖЕН виклик моделі з показу несе явну вибірку, і число живе в Python.
Друкує: скільки шляхів тіла без вибірки лишилось, скільки чисел вибірки написано в показі,
що віддає ендпойнт `паспорт` поруч із промптом і яку вибірку має кожне оголошення задачі.
Запуск: cd джерела && python3 проби/м6_вибірка_шляхом.py"""
import io, json, os, re, sys
ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(ТУТ))
import збирач_промптів as ЗП
import bridge as Б

показ = io.open(os.path.join(os.path.dirname(ТУТ), "показ.html"), encoding="utf-8").read()
тіло = re.search(r"async function _дзвінокП\(([^)]*)\)\{(.*?)\n\}", показ, re.S)
без_вибірки = len(re.findall(r"вибірка \|\| \{\}", показ))
чисел_у_показі = len(re.findall(r"temperature\s*:", показ))
плейсхолдер = показ.count("__ВИБІРКА_ПОКАЗУ__")
# усі виклики _дзвінокП: жоден не має права їхати без третього аргумента чи типової в тілі
виклики = re.findall(r"_дзвінокП\(([^;]*?)\)\)", показ)
з_вибіркою = [в for в in виклики if "вибірка" in в]
пасп = json.loads(Б.виклик("паспорт", {"сценарій": {}, "вимоги": ""}))

print("_дзвінокП: типова в тілі — %s · «вибірка || {}» лишилось: %d · плейсхолдер у показі: %d"
      % ("є" if тіло and "вибірка || ВИБІРКА_П" in тіло.group(2) else "НЕМА", без_вибірки, плейсхолдер))
print("виклики _дзвінокП: %d, з них пересилають вибірку задачі: %d" % (len(виклики), len(з_вибіркою)))
print("чисел temperature, написаних у показ.html: %d (має бути 0 — число в Python)" % чисел_у_показі)
print("ендпойнт `паспорт`: вибірка поруч із промптом = %s" % json.dumps(пасп.get("вибірка"), ensure_ascii=False))
print("перелік ВИБІРКИ: " + json.dumps(ЗП.ВИБІРКИ, ensure_ascii=False) + " · типова: " + ЗП.ВИБІРКА_ТИПОВА)

# оголошення задач: чия вибірка не типова — видно тут, а не в показі (рядок 175: виклик 0 — «стабільна»)
тексти = {ім: io.open(os.path.join(os.path.dirname(ТУТ), ім), encoding="utf-8").read()
          for ім in sorted(os.listdir(os.path.dirname(ТУТ))) if ім.endswith(".py")}
свої = [ім for ім, т in тексти.items() for _ in re.finditer(r"\w+ = _?ЗП_?\.Оголошення\(", т)]
нетипові = sorted(ім for ім in set(свої) if re.search(r'^\s*вибірка="(?!типова)\w+"', тексти[ім], re.M))
print("оголошень задач: %d · не на типовій: %s" % (len(свої), ", ".join(нетипові) or "жодного"))
вади = ([] if пасп.get("вибірка") else ["ендпойнт `паспорт` не віддає вибірку"]) \
      + (["у показі лишилось «вибірка || {}»"] if без_вибірки else []) \
      + (["число temperature написане в показі"] if чисел_у_показі else []) \
      + ([] if плейсхолдер == 1 else ["плейсхолдера вибірки в показі не один"])
print("вади: %d%s" % (len(вади), "".join("\n  ✗ " + x for x in вади)))
sys.exit(1 if вади else 0)
