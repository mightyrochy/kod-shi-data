"""Суд і дріт оцінки однаково бачать названу ошатність та її відсутність."""
import sys
sys.path.insert(0, ".")
import оцінка_образу as О

for сцена in ({"ошатність": [7, 8]}, {"нагода": "робота"}, {}):
    нагода, _ = О._сцена_для_моделі({"сцена": сцена})
    невідомо = О._без_входу({}, сцена, [])
    assert bool(нагода) == ({"input": "occasion"} not in невідомо)
    if "нагода" in сцена:
        assert нагода == {"occasion": "work"}
    if "ошатність" in сцена:
        assert нагода["formality"] == ["smart", "formal"]
        assert "occasion" in О.дані_оцінки({"сцена": сцена})
        суд = {"сцена": сцена, "речі": [{"ід": "ф1"}], "образ": ["ф1"], "суд": {"node": "верх"}}
        assert "She did not name the occasion: do not judge formality" not in О.промпт_оцінки(суд)
print("ошатність, нагода, відсутність: 3/3")
