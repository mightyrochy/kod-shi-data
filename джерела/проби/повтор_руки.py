"""Д-1: чому та сама річ стоїть у картках рук 1 і 2 одного прогону.

Скарга власника 25.09: кардиган sunwin-store ж-08489 у двох картках одного прогону.
Руки 1 і 2 — це той самий каталог і той самий сценарій; розводить їх лише сіль
`міст_рука2.СІЛЬ_РУКИ_2` (сід+23, порядок РІВНИХ) і `різноманітність_пулу.розвести_голови`
(перші ГОЛОВА_РУК речей слота). Проба на трьох сідах друкує: скільки речей спільні в
пулах рук, і який збіг мають ПЕРШІ K речей слота — саме звідти модель бере найчастіше
(див. `повтор_позиція.py`). Поруч — що насправді порівнює `мета.контроль.пул_спільних`.
Прогін: python3 проби/повтор_руки.py       (~1 хв)
"""
import json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed as Ф, bridge as B, міст_пакет as МП, міст_рука2 as МР, різноманітність_пулу as РП
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), каталог=Ф.каталог_на_диску("каталог_повний.xml"))
print("СІЛЬ_РУКИ_2 = %d (міст_рука2.py:66) · ГОЛОВА_РУК = %d (різноманітність_пулу.py:380)"
      % (МР.СІЛЬ_РУКИ_2, РП.ГОЛОВА_РУК))
for сід in (7, 4242, 31337):
    r = json.loads(B.виклик("запити", json.dumps(dict(вх, сід=сід), ensure_ascii=False)))
    пули = [{с: [x.get("id") for x in v] for с, v in p["кандидати"].items()}
            for p in МП._КЕШ_ПАКЕТА.values() if p.get("кандидати")]
    if len(пули) < 2:
        print("сід %-6s каталогу в обидві руки не подано" % сід); continue
    a, b = пули[0], пули[1]
    ва, вб = {i for v in a.values() for i in v}, {i for v in b.values() for i in v}
    рядок = ["сід %-6s пул рук %d і %d, спільних %d (%.0f %% пулу руки 1)"
             % (сід, len(ва), len(вб), len(ва & вб), 100.0 * len(ва & вб) / len(ва))]
    for K in (1, 3, 5, 10):
        сп = sum(len(set(a[с][:K]) & set(b.get(с, [])[:K])) for с in a)
        всь = sum(len(a[с][:K]) for с in a)
        рядок.append("перші %-2d — %2.0f %%" % (K, 100.0 * сп / всь))
    print("   ".join(рядок))
    поломка = (r.get("поломка") or {}).get("назва")
    print("      поломка руки 2: %s; донор (інша людина) у жеребі: %s"
          % (поломка, "так" if поломка == "донор" else "ні — руки судять ОДНУ людину"))
