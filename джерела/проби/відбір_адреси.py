"""Міряє незмінність виданих адрес після needed та явну ціль ремонту."""
import json, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import міст_пакет as М, пакет_моделі as П, повнота_образу as О


def головна():
    """Розширює пакет двома крамницями й перевіряє попередні адреси та вибір."""
    пак = dict(кандидати={'верх': [dict(id='основа@z')], 'сумка': []})
    старі, _ = П.номери_речей(пак['кандидати']); втрати = 0
    for слот, ід in [('верх', 'друга@y'), ('сумка', 'перша@a'), ('верх', 'третя@a')]:
        М.додати_за_запитом(пак, слот, dict(id=ід), ['bag'])
        нові, _ = П.номери_речей(пак['кандидати'])
        втрати += sum(нові[і] != н for і, н in старі.items())
        старі = нові
    переставлені = {с: list(reversed(р)) for с, р in reversed(list(пак['кандидати'].items()))}
    втрати += старі != П.номери_речей(переставлені)[0]
    образи = [dict(ід=і, речі=['а', 'б'], структура=dict(ок=False,
                  блокери=[dict(код='слот_двічі')])) for і in ('о1', 'о2')]
    ремонт = О.вердикт_повноти(dict(образи=образи), обрано='о2')
    чужий = [о['ід'] for о in ремонт['образи']] != ['о2']
    М.додати_за_запитом(пак, 'верх', dict(id='третя@a'), ['bag'])
    дубль = старі != П.номери_речей(пак['кандидати'])[0]
    print(json.dumps(dict(зсунуті_адреси=втрати, чужий_ремонт=int(чужий),
                         дубль_зсуває=int(дубль)), ensure_ascii=False))
    return int(bool(втрати or чужий or дубль))


if __name__ == '__main__':
    sys.exit(головна())
