"""Л-6, ПІСЛЯ В-7 (PR #345): «усі кольори чудово пасують» поруч із «колір не з твоєї палітри».
До (`проби/шлях_оцінка_суперечність.py`): сторожів над текстом моделі три, жоден не звіряє
текст із вердиктом коду; «не суперечи» стояло побажанням промпта.
Після: відповідь задачі `ОЦІНКА` несе твердження КОДАМИ (about, items, id зміни, verdict), і
`оцінка_образу.прийняти_оцінку` звіряє їх із судом коду; суперечне на картку не йде.
Запуск із `джерела`: python3 проби/шлях_оцінка_екран_сторож.py"""
import sys, json; sys.path.insert(0, '.')
import оцінка_образу as О
exec(open('проби/шлях_оцінка_екран_образ.py', encoding='utf-8').read().split('for назва, екран')[0].split('"""', 2)[2])
с = О.суд(dict(вх, речі=речі, сценарій_оцінки={}, крамниця=False))
поза = [р["ід"] for р in с["речі"] if (р.get("палітра") or {}).get("стан") == "поза палітрою"]
# «два різні білі» (ф2 сорочка + ф5 ботильйони): КОЛ-3 (рядок 650) — площа взуття не виміряна,
# тож K-COL-06 тут не знахідка, а «без входу»; суперечність «білі пасують» ловить K-COMP-04 на ф2
_кол06 = [з for з in с["суд"]["findings"] if з["правило"] == "K-COL-06"]
_кол06_бв = [б for б in с["без_входу"] if "K-COL-06" in (б.get("rule") or ()) and "ф5" in json.dumps(б, ensure_ascii=False)]
print("код: поза палітрою %s; K-COL-06: %s; про пари: %s; нагоди й погоди вона не назвала" % (
      "+".join(поза), "знахідка проти " + "+".join(_кол06[0]["речі"]) if _кол06 else
      "без входу (площа ф5 не виміряна)" if _кол06_бв else "мовчить",
      ", ".join("%s %s" % (з["правило"], "+".join(з["речі"])) for з in с["суд"]["findings"]
                if len(set(з.get("речі") or [])) > 1) or "—"))
# відповідь моделі, що повторює запис 26.09: «усі кольори пасують» — кодами
відп = {"answer": "All these colors go together beautifully and suit you.", "verdict": "wear_as_is",
        "works": [{"about": "palette", "items": ["ф1", "ф2", "ф3", "ф4", "ф5"], "text": "Every color is yours."},
                  {"about": "colors_together", "items": ["ф2", "ф5"], "text": "The two whites match."},
                  {"about": "weather", "items": ["ф1"], "text": "The jacket is just right for the weather."},
                  {"about": "formality", "items": ["ф5"], "text": "Perfect for an everyday look."},
                  {"about": "contrast", "items": ["ф2"], "text": "Your face is lit by the light shirt."}],
        "change": [{"id": "з7", "text": "Swap the bag."}], "unknown": []}
р = О.прийняти_оцінку(json.dumps(відп), с)
print("тверджень «що вдало» від моделі: %d; на картку пройшло: %d (%s)" % (
      len(відп["works"]), len(р["картка"]["вдало"]), ", ".join(п["про"] for п in р["картка"]["вдало"]) or "—"))
for х in р["сторож"]:
    print("  знято %-9s %-16s — %s" % (х["де"], х.get("про") or "", х["чому"]))
print("змін від моделі %d, перевірених кодом серед них %d" % (len(відп["change"]), len(р["картка"]["змінити"])))
print("межа сторожа (сказано у звіті): звіряє %(звіряє)s, не читає %(не_читає)s" % р["сторож_межа"])
знято = {х["де"] for х in р["сторож"]}
assert {"works[0]", "works[1]", "works[2]", "works[3]"} <= знято, "сторож пропустив суперечне твердження"
assert not р["картка"]["змінити"], "неперевірена кодом зміна дійшла на картку"
print("→ до: суперечність не ловив ніхто; після: кожне твердження звірено з судом, суперечне знято з назвою.")
