def _репри(x, шлях="в"):
    """(шлях, рядок) для кожного РЯДКА всередині `x`, що несе `repr` словника чи списку.

    Рядок відповіді мосту — це текст або код; `repr` у ньому означає, що десь обʼєкт
    внутрішньої мови склеївся в текст через «%s» і поїхав на екран як є."""
    якщо = lambda т: any(п in т for п in РЕПР)
    if isinstance(x, str):
        return [(шлях, x)] if якщо(x) else []
    if isinstance(x, dict):
        return [r for к, v in x.items() for r in _репри(v, "%s.%s" % (шлях, к))]
    if isinstance(x, (list, tuple)):
        return [r for і, v in enumerate(x) for r in _репри(v, "%s[%d]" % (шлях, і))]
    return []


