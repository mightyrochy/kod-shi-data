# -*- coding: utf-8 -*-
"""Д-1: чому семплер віддає ті самі речі — стеля досяжності слота.

`семплер.вибрати_зі_слота` ділить слот на страти (гілка · тип · зона), страту — на
магазини, і бере ПО ОДНІЙ речі з групи по колу; усередині групи порядок дає
`_розкидом` — перші три це найдешевша, найдорожча й медіанна, і вони від сіда НЕ
залежать (семплер.py:118–149). Коли квота менша за кількість груп, прогін бере по
одній речі з групи — тобто ЗАВЖДИ найдешевшу. Проба друкує на живому пулі речей,
страт, груп (страта × магазин), віддану квоту й СТЕЛЮ ДОСЯЖНОСТІ: скільки різних
речей слот узагалі здатен віддати при цій квоті, на будь-якому сіді.
Прогін: python3 проби/повтор_страти.py      (~30 с)
"""
import collections, json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed as Ф, bridge as B, міст_пакет as МП, семплер as СМ
вхід, _вибрати = {}, СМ.вибрати
def _пійм(кандидати, бюджет, **кв):
    вхід.setdefault("пул", кандидати); return _вибрати(кандидати, бюджет, **кв)
СМ.вибрати = _пійм
вх = dict(json.load(open("стенд_вх.json", encoding="utf-8")), сід=4242, каталог=Ф.каталог_на_диску("каталог_повний.xml"))
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
СМ.вибрати, пул = _вибрати, вхід["пул"]
пак = [p for p in МП._КЕШ_ПАКЕТА.values() if p.get("кандидати")][0]
квоти = {с: len(v) for с, v in пак["кандидати"].items()}   # скільки семплер ВІДДАВ на прийнятому зрізі
print("прийнятий зріз: %d речей на %d слотів; ПІДЛОГА_СЛОТА = %d (семплер.py:30)"
      % (sum(квоти.values()), len(квоти), СМ.ПІДЛОГА_СЛОТА))
print("%-14s %7s %7s %7s %7s %10s" % ("слот", "речей", "страт", "груп", "квота", "досяжно"))
for с in sorted(пул, key=lambda к: -len(пул[к])):
    групи = collections.defaultdict(list)
    for r in пул[с]:
        групи[(СМ._страта(r), СМ._магазин(r))].append(r)
    к = квоти.get(с, 0)
    на_групу = max(1, -(-к // max(len(групи), 1)))   # скільки разів коло встигне дійти до групи
    досяжно = sum(min(len(г), на_групу) for г in групи.values())
    print("%-14s %7d %7d %7d %7d %7d %2.0f %%" % (с, len(пул[с]), len({к_ for к_, _ in групи}), len(групи),
          к, min(досяжно, len(пул[с])), 100.0 * min(досяжно, len(пул[с])) / len(пул[с])))
print("РАЗОМ %d речей доступно, віддано %d. Де «досяжно» мало більше за «квоту», слот віддає майже "
      "ТОЙ САМИЙ набір на будь-якому сіді: сід переставляє групи, а першу річ у групі — ні."
      % (sum(len(v) for v in пул.values()), sum(квоти.values())))
