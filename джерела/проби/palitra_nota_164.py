"""Рядок 164 + Ч-1 (аудит/ПРОДУКТ.md п.12): що жінка читає під плитками схем на екрані «Палітра».
Рівень контрасту × гілка розвилки (зі statement-гілками й мисматчем) × яскравий макіяж
так/ні → ПОВІДОМЛЕННЯ КОДАМИ (`нота_кодами`), з якого речення складає мовна модель
(`показ.html`: `повідомленнямП`, інакше сире `застереження`/`коли`). Пара без заяв падає
тут, а не мовчить на екрані; код заяви поза словником `внутрішня_мова.ЗАЯВИ` — теж падіння.
Фраз українською код тут уже не пише — це й міряє `проби/кошик_в_лічба.py`.
Запуск: cd джерела && python3 проби/palitra_nota_164.py"""
import os, sys
ДЖЕРЕЛА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ДЖЕРЕЛА)
import палітра_розвилка as Р
import внутрішня_мова as ВМ

РІВНІ = (("низький", 10.0), ("середній", 33.0), ("високий", 60.0))
сире = lambda г: (г.get("застереження") if (г.get("застереження") or "—") != "—" else None) or г.get("коли") or ""

рядків, заяв = 0, 0
без_заяв, поза_словником, приклади = [], [], []
for рівень, gap in РІВНІ:
    for мк in (None, {"рівень": "яскравий"}):
        особа = dict(рівень=рівень, value_gap=gap, colour_contrast=0.5, макіяж=мк)
        # statement дає всі шість гілок відразу; під conventional ті самі шість
        # приходять через `явні`, і заяви ті самі — ключ не залежить від наміру
        for г in Р.розвилка(особа, intent="statement")["гілки"]:
            рядків += 1
            п = г.get("нота_кодами")
            з = (п or {}).get("statements") or []
            if not з:
                без_заяв.append((рівень, bool(мк), г["схема"]))
                continue
            заяв += len(з)
            поза_словником += [(г["схема"], x.get("code")) for x in з if x.get("code") not in ВМ.ЗАЯВИ]
            if (п or {}).get("kind") not in ВМ.ВИДИ_ПОВІДОМЛЕНЬ:
                поза_словником.append((г["схема"], "вид:%s" % (п or {}).get("kind")))
            if len(приклади) < 3:
                приклади.append("%s/%s: сире «%s» → заяви %s"
                                % (рівень, г["схема"], сире(г)[:60], [x["code"] for x in з]))

print("пар пал-нота (3 рівні × гілки × макіяж 2): %d · заяв разом: %d · без заяв: %d · "
      "кодів поза словником: %d" % (рядків, заяв, len(без_заяв), len(поза_словником)))
for п in приклади + ["БЕЗ ЗАЯВ: %s" % (п,) for п in без_заяв] \
        + ["ПОЗА СЛОВНИКОМ: %s" % (п,) for п in поза_словником]:
    print("  ", п)
sys.exit(1 if (без_заяв or поза_словником) else 0)
