# -*- coding: utf-8 -*-
"""Рядок 164: що жінка читає під плитками схем на екрані «Палітра». Рівень
контрасту × гілка розвилки (зі statement-гілками й мисматчем) × яскравий макіяж
так/ні → рядок, який показ кладе в `пал-нота` (`показ.html`: `_г.людською`,
інакше сире `застереження`/`коли`). Машинних слів ПІСЛЯ мусить бути 0; пара без
людського рядка падає тут, а не мовчить на екрані.
Запуск: cd джерела && python3 проби/palitra_nota_164.py"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import палітра_розвилка as Р

МАШИННЕ = re.compile(r"[A-Za-z]{3,}|\b[A-ZА-ЯІЇЄҐ]{1,2}-[A-ZА-ЯІЇЄҐ]{2,6}-\d{2}\b|ПРОВЕНАНС")
РІВНІ = (("низький", 10.0), ("середній", 33.0), ("високий", 60.0))
сире = lambda г: (г.get("застереження") if (г.get("застереження") or "—") != "—" else None) or г.get("коли") or ""

рядків = до = після = 0
без_людського, приклади = [], []
for рівень, gap in РІВНІ:
    for мк in (None, {"рівень": "яскравий"}):
        особа = dict(рівень=рівень, value_gap=gap, colour_contrast=0.5, макіяж=мк)
        # statement дає всі шість гілок відразу; під conventional ті самі шість
        # приходять через `явні`, і текст той самий — ключ не залежить від наміру
        for г in Р.розвилка(особа, intent="statement")["гілки"]:
            рядків += 1
            с, л = сире(г), г.get("людською")
            if not л:
                без_людського.append((рівень, bool(мк), г["схема"]))
            зн_до, зн_після = МАШИННЕ.findall(с), МАШИННЕ.findall(л or с)
            до += bool(зн_до); після += bool(зн_після)
            if зн_до and len(приклади) < 3:
                приклади.append("%s/%s: ДО «%s» → ПІСЛЯ «%s»"
                                % (рівень, г["схема"], с[:70], (л or с)[:70]))
            if зн_після:
                print("  МАШИННЕ ПІСЛЯ:", рівень, г["схема"], зн_після, "→", (л or с)[:120])

print("рядків пал-нота (3 рівні × гілки × макіяж 2): %d · з машинними словами ДО: %d · "
      "ПІСЛЯ: %d · без людського рядка: %d" % (рядків, до, після, len(без_людського)))
for п in приклади + ["БЕЗ ЛЮДСЬКОГО: %s" % (п,) for п in без_людського]: print("  ", п)
sys.exit(1 if (після or без_людського) else 0)
