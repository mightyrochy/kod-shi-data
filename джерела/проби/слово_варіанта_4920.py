лічба, зміни, залишок, без, історична = [0, 0], [], [], 0, [0, 0]
for р in речі:
    поле = р.get("колір_сирий") or р.get("колір_назва") or ""
    if len([ч for ч in поле.split(",") if ч.strip()]) < 2: continue
    з = збагачення.get(р["id"])
