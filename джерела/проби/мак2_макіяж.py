# -*- coding: utf-8 -*-
"""МАК-2 (рядок 258, П-4): порада про макіяж за нагодою й контрастом обличчя. Друкує факт на стенд_вх.json:
профіль (низький/високий контраст) × нагода × макіяж (не сказано/яскравий) — заява поради в `style_rules`
пакета руки 1 і чи тема «макіяж» доречна в розмові сценарію; для ділової нагоди — скільки приобличчевих
прикрас (near ≥ 0.6) у пулі руки 1 за слотами (вхід П-5). Запуск: cd джерела && python3 проби/мак2_макіяж.py"""
import sys, pathlib, json, collections
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import feed as Ф, bridge as B, паспорт_нагоди as ПН, колір_річ as КР
Н = ("visible_makeup_helps_low_contrast", "bright_makeup_softer_for_work")
вх = json.load(open(pathlib.Path(__file__).resolve().parent.parent / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml"); вх["гілка"] = 0
ПРОФІЛІ = {"низький": вх["волосся"], "високий": ["#1b1512"]}
СЦЕНИ = {"офіс": dict(нагода="робота", місце="офіс_корпоративний", година=9, дрес_код="business_casual"),
         "співбесіда": dict(нагода="співбесіда", місце="співбесіда", година=11),
         "побачення": dict(нагода="побачення", місце="ресторан", година=19.5, ошатність=[6, 7]),
         "прогулянка": dict(нагода="прогулянка", година=12, ошатність=[2, 3]),
         "похорон": dict(місце="похорон", година=11, ошатність=[5, 6])}
for п, волосся in ПРОФІЛІ.items():
    for с, сц in СЦЕНИ.items():
        for мк in (None, "яскравий"):
            д = dict(вх, волосся=волосся, сценарій=dict(сц, **({"макіяж": {"рівень": мк}} if мк else {})))
            р = json.loads(B.виклик("запити", json.dumps(д, ensure_ascii=False)))
            Б = json.loads(р["B"]); ст = [(x if isinstance(x, str) else next(iter(x))) for x in Б["style_rules"]]
            рів = {"low": "низький", "medium": "середній", "high": "високий"}.get(Б["person"]["contrast"])
            тема = "макіяж" in ПН.теми_дозволені(д["сценарій"], контраст=рів)
            print("%-8s %-6s %-10s %-9s | бриф %-36s | тема «макіяж» у розмові: %s"
                  % (п, Б["person"]["contrast"], с, мк or "—", [к for к in Н if к in ст] or "—", тема))
            if п == "низький" and с == "офіс" and not мк:
                кат = B.каталог_останнього_пакета()
                біля = collections.Counter(c.get("слот") for c in кат
                                           if КР.SLOT_NEAR_FALLBACK.get(c.get("слот"), 0) >= 0.6
                                           and c.get("слот") in ("прикраси", "сережки", "намисто", "кольє", "брошка"))
                print("   пул руки 1 (офіс): приобличчеві прикраси за слотами:", dict(біля) or "—")
