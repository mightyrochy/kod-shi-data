# -*- coding: utf-8 -*-
"""6950/6952: повний RAW/CLEAN штатним фідом; головна прикраса не ювелірна."""
import collections, gzip, pathlib, shutil, sys, tempfile
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import feed as Ф, palettes as П, внутрішня_мова as М, каталог_розбір_прогін as Р, аксесуари_край as К

def вимір(мітка, шлях):
    """Друкує факти каталогу й тих самих кодових перевірок з типом та без типу."""
    офери, _ = Ф.читати_yml(шлях)
    база = Ф._прочитати_каталог(шлях, ліміт_фото=0, кеш="кеш.json", збагачення=Ф.читати_збагачення())
    головні = [р for р in база["каталог"] if М.тип_на_голові(р.get("тип"))]
    іди = {р["id"] for р in головні}
    сирі = [о for о in офери if о["id"] in іди]
    ланцюги = [sum("ланцюг_см" in Ф.аксесуарні_довжини(о, Ф.слот(о), т(о)) for о in сирі)
               for т in (lambda о: None, lambda о: Ф.тип_речі(о, Ф.слот(о)))]
    метал = [р for р in головні if р.get("метал")]
    print(мітка, "суд_краю_головних", sum(bool(К.кольє_проти_горловини({"висоти": {"плечі": 140}},
          [dict(р, ланцюг_см=41), {"слот": "верх", "верх_см": 119.5, "край_джерело": "річ"}])) for р in головні), flush=True)
    група = next(п for н, _, п in Р.ГРУПИ if н == "прикраси")
    print(мітка, "офери/записи", база["офферів"], len(база["каталог"]), "типи", dict(collections.Counter(р["тип"] for р in головні)),
          "ланцюг без_типу/з_типом", ланцюги, "метал_вхід", len(метал), "метал_ювелірний", sum(П.слот_металу(р["слот"], р["тип"]) for р in метал),
          "поля_ювелірні", sum(any(к in р for к in ("частка_металу", "колір_вставки", "метал_спір")) for р in головні),
          "головні_у_ювелірній_групі", sum(група(о, Ф.слот(о)) for о in сирі),
          "невідомі_типи_прикраси", sum(р["слот"] == "прикраси" and М.код("item_type", р.get("тип")) is None for р in база["каталог"]), flush=True)
    for і in ("ж-07561@honchstudio.com", "ж-07574@honchstudio.com", "ж-11719@theoriginals.com.ua", "ж-11758@theoriginals.com.ua"):
        р = next((р for р in база["каталог"] if р["id"] == і), {})
        print(мітка, і, {к: р.get(к) for к in ("тип", "ланцюг_см", "метал", "частка_металу", "колір_вставки", "метал_спір")}, flush=True)

if __name__ == "__main__":
    корінь = pathlib.Path(__file__).resolve().parents[2]
    with tempfile.TemporaryDirectory(prefix="головні6950-") as тека:
        сирий = pathlib.Path(тека) / "сирий.xml"
        with gzip.open(корінь / "каталог_повний.xml.gz", "rb") as вх, сирий.open("wb") as вих:
            shutil.copyfileobj(вх, вих)
        вимір("RAW", str(сирий))
        вимір("CLEAN", Ф.каталог_на_диску("каталог_повний.xml"))
    for тип in (None, "unknown", "каблучка", "обруч", "заколка"):
        print("код_контроль", тип, "слот_металу", П.слот_металу("прикраси", тип), "на_голові", М.тип_на_голові(тип))
