"""Корінь Е2-частина-дня, крок 3: записані перші ходи розмови крізь шов без моделі — правила дня й вечора, як у базі
знань: щабель смуги пулу, суду й брифу (`формальність.смуга_ошатності`, підйом K-KOH-06) і ліміт відкритих зон без
поля моделі (`ліміт_відкритих_зон`, K-KOH-10); кожна сцена ще й парою — та сама з `пора` день і вечір (весілля,
ділова гілка й письмова вимога — окремо: їх вечір не підіймає).
argv[1] — корінь дерева коду (типово — це)."""
import sys, os, json, glob, warnings, inspect, collections
warnings.filterwarnings("ignore")
ТУТ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(sys.argv[1] if len(sys.argv) > 1 else ТУТ, "джерела"))
import мовний_шар as М, паспорт_нагоди as ПН, формальність as Ф
З_ПОРОЮ = "пора" in inspect.signature(Ф.ліміт_відкритих_зон).parameters
щабель = lambda н: (lambda с: Ф.щабель_смуги(с[0]) if с else None)(Ф.смуга_ошатності(н))
зони = lambda н: Ф.ліміт_відкритих_зон(н.get("відкриті_зони"), *([н.get("пора")] if З_ПОРОЮ else []))[0]
л = collections.Counter()
for ф in sorted(glob.glob(os.path.join(ТУТ, "аудит/**/VIDPOVIDI/seed*_01_мовний_шар_хід_розмови.txt"), recursive=True)):
    т = open(ф, encoding="utf8", errors="replace").read().split("── ВІДПОВІДЬ", 1)[-1]
    try:
        п = М.паспорт_з_шару(М.прийняти_розмову(т[т.find("{"):т.rfind("}") + 1])["внутрішня"], {}, слова_ходу=[])
        н = ПН.з_показу({}, п["паспорт"])[0]
    except Exception:
        л["виняток"] += 1
        continue
    л["ходів"] += 1
    щм = Ф.один_щабель(*н["ошатність"]) if isinstance(н.get("ошатність"), (list, tuple)) else None
    вечір, весілля = н.get("пора") in ("вечір", "ніч"), н.get("нагода") in ("весілля_гість", "весілля")
    if щм and щабель(н) != щм:
        л["щабель смуги ≠ щабля моделі%s" % ("" if вечір else ": удень")] += 1
        л["  з них весілля"] += весілля
        л["  з них ділова гілка"] += н.get("гілка_ошатності") == "business"
    if щм:
        д, в = (щабель(dict(н, пора=х)) for х in ("день", "вечір"))
        к = ("весілля" if весілля else "ділова" if н.get("гілка_ошатності") == "business"
             else "письмова вимога" if Ф.код_дрес(н.get("дрес_код")) else щм)
        л["пара день/вечір %s: %s" % (к, "вечір вище" if в != д else "той самий щабель")] += 1
    if not н.get("відкриті_зони"):
        л["зони без поля, ця сцена (%s): %d" % ("вечір" if вечір else "день/без пори", зони(н))] += 1
        л["пара зон день/вечір без поля: %d/%d" % (зони(dict(н, пора="день")), зони(dict(н, пора="вечір")))] += 1
for к in sorted(л):
    print("%s: %d" % (к, л[к]))
