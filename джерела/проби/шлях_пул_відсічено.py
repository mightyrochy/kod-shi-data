"""Розбір 3/8: що пул зняв до першого виклику моделі і в якій лічбі.

`пакет_моделі.відсікти_пул` рахує КАНДИДАТІВ (те, що вже пройшло вікна
композитора), а рядок «жорстке «ні» людини» додається окремо по КАТАЛОГУ — дві
різні стадії лягають в одну лічбу `відсічено`. Проба друкує лічбу справжніх
прогонів власника і позначає рядки, де причина — не випадок і не її слово, а
показ (крамниця не дає знімків, ціни нема).
Прогін: python3 проби/шлях_пул_відсічено.py
"""
import json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ)
os.chdir(ТУТ)
import пакет_моделі as ПМ
ПОКАЗ = ("знімк", "ціни нема")
ФАЙЛ = os.path.join(os.path.dirname(ТУТ), "аудит", "тести", "власник_2026-09-25",
                    "verdykty-0phxvk-2026-09-25-2012.json")
for пр in json.load(open(ФАЙЛ, encoding="utf-8"))["прогони"]:
    сп = пр["спільне"]
    ет = (сп.get("етапи") or {}).get("прогін") or {}
    від = (ет.get("відсічено") or {}).get("лічба") or {}
    if not від:
        continue
    print("прогін розклад %s (%s): у пулі лишилось %s речей, знято %d парами"
          % (сп.get("розклад"), сп.get("дата"), ет.get("пул_речей"), sum(від.values())))
    for причина, n in sorted(від.items(), key=lambda кв: -кв[1]):
        мітка = "  ← причина ПОКАЗУ, не випадку" if any(с in причина for с in ПОКАЗ) else ""
        print("   %5d  %s%s" % (n, причина, мітка))
    print("   слоти, що випали зовсім: %s" % (ет.get("слоти_випали") or "—"))
print("ПРИЧИНА_НЕ_ЦЯ = %r; підлога вибірки семплера = %d"
      % (getattr(ПМ, "ПРИЧИНА_НЕ_ЦЯ", "—"), __import__("семплер").ПІДЛОГА_СЛОТА))
