# -*- coding: utf-8 -*-
"""ЗАМІР-Д (02.10): на кожен прогін <тека>/<прогін>/{вердикти.txt, лог.txt} — час збирання, намір/мета паспорта, схема руки 1–2 (вийшла?),
чи є проза на картці (руки 1–4), чужа мова/чужий образ за звірками стенда, червоні звірки. Нічого не викликає."""
import json, re, sys, glob, os
for д in sorted(glob.glob(sys.argv[1] + "/*/")):
    н = os.path.basename(д.rstrip("/")); ф = д + "вердикти.txt"; л = open(д + "лог.txt", encoding="utf-8").read() if os.path.exists(д + "лог.txt") else ""
    if not os.path.exists(ф): print(н, "— нема вердиктів"); continue
    D = json.load(open(ф, encoding="utf-8")); сп = D["спільне"]; п = сп.get("паспорт", {}); В = {str(в["рука"]): в for в in D["прогони"][0]["вердикти"]}
    час = re.search(r"чотири картки за ([\d.]+) с", л); ру = []
    for р in "12":
        в = В.get(р); ру.append(f"р{р}:" + ("нема" if not в else f"{в['пал_схема_руки']}/вийшла={в['схема_вийшла']}/текст={len(в.get('опис') or '')}/ітер={в['ітерацій']}"))
    пр = [р for р in "1234" if р in В and len((В[р].get("опис") or "").strip()) < 30]
    чер = re.findall(r"^\s+✗ (.{0,110})", л, re.M)
    чуж = [x for x in чер if "чуж" in x or "приймає" in x or "прийняв" in x or "проза" in x or "латиниц" in x]
    print(f"{н}: {час.group(1) if час else '?'} с · намір={п.get('намір')} мета={п.get('мета')} · {' '.join(ру)} · без_прози={пр or 0} · звірки_проза/чужий_образ={чуж or 0} · червоних={len(чер)}")
