# -*- coding: utf-8 -*-
"""Візерунок опису з фото в ЖИВОМУ ШЛЯХУ: леопард не стає «квітковим».

Спіймано на вето Н-V07-023 (18.09.2026): `verify.клас_мотиву` на назві «Спідниця
шовкова в леопардовому принті» дає «анімалістичний», а в пакеті та сама річ стояла
«квітковий» — поле опису з фото перекривало слово крамниці без умов, а поле моделі
«анімалістичний» не видає ніколи (див. `feed._візерунок_фото`). Будь-яке правило чи
вето на «анімалістичний» мовчало на всіх леопардових речах каталогу.
Проба кличе той самий шлях, що продукт (`bridge.виклик("запити", стенд_вх)`), і
стверджує на ПАКЕТІ:
  1) кожна річ, чия назва каже «леопард», несе «анімалістичний»;
  2) жодна річ, чиє слово називає сім'ю ДРУКУ, не дістала від фото іншої сім'ї
     друку мовчки: або слово лишилось (з `візерунок_спір`), або фото з ним згодне.
Запуск із теки `джерела`: `python3 проби/zbah_візерунок.py`."""
import sys, pathlib, collections
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ, bridge as B, feed as F

ПВ.стенд(гілка=0)
кат = B.каталог_останнього_пакета()
лічба = collections.Counter(c.get("візерунок") for c in кат)
print("речей у пакеті %d; анімалістичний %d; спорів слова з фото %d"
      % (len(кат), лічба.get("анімалістичний", 0), sum(1 for c in кат if c.get("візерунок_спір"))))

лео = [c for c in кат if "леопард" in (c.get("назва") or "").lower()]
хибні = [(c["назва"][:50], c.get("візерунок")) for c in лео if c.get("візерунок") != "анімалістичний"]
print("ФАКТ · «леопард» у назві: %d речей, з них не «анімалістичний»: %d" % (len(лео), len(хибні)))
assert лео and not хибні, хибні

НЕ_ДРУК = set(F._НЕ_СІМ_Я_МОТИВУ) | set(F._ДЕКОР_МОТИВУ)
перекриті = [(c["назва"][:50], c["візерунок_крамниці"], c["візерунок"]) for c in кат
             if c.get("візерунок_джерело") == "фото"
             and c.get("візерунок_крамниці") not in НЕ_ДРУК
             and c.get("візерунок") not in НЕ_ДРУК
             and c["візерунок"] != c["візерунок_крамниці"]]
print("ФАКТ · сім'я друку слова, мовчки перекрита іншою сім'єю з фото: %d" % len(перекриті))
assert not перекриті, перекриті[:5]
спір = next((c for c in кат if c.get("візерунок_спір")), None)
assert спір and спір["візерунок_спір"]["крамниця"] == спір["візерунок"], спір
print("приклад спору: «%s» — лишилось слово «%s», фото казало «%s»"
      % (спір["назва"][:50], спір["візерунок"], спір["візерунок_спір"]["фото"]))
