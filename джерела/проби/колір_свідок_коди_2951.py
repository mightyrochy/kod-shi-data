"""КОЛІР-ФІД-3 (рядок 2951): свідок кольору (`колір_не_вимір.свідок`) — код чи українське слово, на
`каталог_повний` (рука 1). Друкує: розподіл свідка в записах каталогу, свідок запису кольору для правил
(`колір_річ.запис_кольору`) і джерело на дроті моделі (`дріт_моделі._не_вимір`); українських рядків — скільки.
Запуск із джерела/: python3 проби/колір_свідок_коди_2951.py"""
import sys, re, collections as K
sys.path.insert(0, "."); import feed as F, фід_каталог as ФК, колір_річ as КР, дріт_моделі as ДМ
F.каталог_на_диску("каталог_повний.xml")
кат = ФК._прочитати_каталог("каталог_повний.xml", 0)["каталог"]
нв = [r["колір_не_вимір"] for r in кат if r.get("колір_не_вимір")]
укр = lambda с: bool(re.search("[а-щьюяєіїґ]", str(с or "")))
св = K.Counter(н.get("свідок") for н in нв)
print("речей:", len(кат), "· з колір_не_вимір:", len(нв), "· свідок:", dict(св.most_common()))
print("  свідок українським рядком:", sum(n for с, n in св.items() if укр(с)))
зк = K.Counter(КР.запис_кольору(r)["свідок"] for r in кат if КР.запис_кольору(r))
print("запис_кольору.свідок:", dict(зк.most_common()))
дріт = K.Counter((ДМ._не_вимір(н) or {}).get("source") for н in нв)
print("дріт моделі source:", dict(дріт.most_common()), "· невідомих:", дріт.get(ДМ.U, 0))
