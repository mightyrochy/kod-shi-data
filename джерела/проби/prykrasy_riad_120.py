# -*- coding: utf-8 -*-
"""Рядок 120: ручний рядок «Прикраси» — шість слів жінки. ДО: рядка в показі не було
(`grep прикраси показ.html` = 0), поле задавалось ЛИШЕ словами розмови. ПІСЛЯ: слово плитки
їде ключем `сценарій.прикраси`; друкуємо паспорт, роботу фільтра пулу, пул до моделі й суд;
хвіст — звірка двох списків. Запуск із `джерела`: python3 проби/prykrasy_riad_120.py"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, pipeline as PL, feed as Ф, суд_блиск as СБ, композитор_слоти as КС

вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["каталог"] = Ф.каталог_на_диску("каталог_brief.xml")
сц = dict(нагода="побачення", місце="ресторан_районний", година=19, темп_c=12)
F = B._збірка(вх)[0]
E = [dict(річ="сережки-1", слот="сережки", метал="золото", near=0.9, площа=0.01, lab=(75.0, 5.0, 30.0))]
# третя річ — без слова металу, як 121 ювелірна з 260 у каталозі
РЕЧІ = [dict(id=i, слот="сережки", метал=м) for i, м in (("a", "золото"), ("b", "срібло"), ("c", None))]
def пул(пасп):
    """(ювелірних у пулі, слотів, скільки з ПЕРШИХ трьох у слоті — без слова металу)."""
    r = json.loads(B.виклик("запити", json.dumps(dict(вх, сценарій=dict(сц), паспорт=пасп), ensure_ascii=False)))
    за_ід = {c.get("id"): c for c in B.каталог_останнього_пакета()}
    ю = {с: v for с, v in r["кандидати"].items() if с in Ф._МЕТАЛ_СЛОТИ}
    чоло = sum(1 for v in ю.values() for x in v[:3] if not (за_ід.get(x["id"]) or {}).get("метал"))
    return sum(map(len, ю.values())), len(ю), чоло
# шість слів рядка + «інші» (старе значення: ЖОДЕН збережений паспорт не має зламатись)
for слово in ("золото", "срібло", "перли", "етно", "без прикрас", "хай обере стилістка", "інші"):
    від_моделі = "невідомо" if слово == "хай обере стилістка" else слово
    п = PL.паспорт_з_json(json.dumps(dict(нагода="побачення", прикраси=від_моделі)), сц, "побачення")
    речі, нота = КС._за_бажаним_металом(list(РЕЧІ), "сережки", None if п["прикраси"] == "невідомо" else п["прикраси"])
    n, слотів, чоло = пул(п); зн = СБ.метали(E, F, драп=dict(метал="срібло"), прикраси=п["прикраси"])
    print("«%-20s» → паспорт=%-12s · фільтр: %-56s · пул %2d у %d слотах, без металу в чолі %2d · суд: %s"
          % (слово, п["прикраси"], (нота or "бажання нема — пул як доти")[:56], n, слотів, чоло,
             "; ".join("%s %s %.2f" % (z["правило"], z.get("регістр"), z["сила_нп"]) for z in зн) or "мовчить"))
    assert п["прикраси"] == від_моделі, п["прикраси"]                     # «інші» й далі приймається
    if слово == "без прикрас": assert n == 0 and слотів == 0 and речі == [], "прикрас не має лишитись"
    if слово in ("перли", "етно"): assert речі[0]["id"] == "c" and n > 0, "без слова металу — перша"
    if слово == "хай обере стилістка": assert п["прикраси"] == "невідомо" and n > 0, "свідомий вибір"
_пок = open("показ.html", encoding="utf-8").read()   # два списки різними мовами: плитки ↔ канон
_бл = re.search(r"const ПРИКРАСИ_П = \[(.+?)\];", _пок, re.S).group(1)
_жс, _кан = re.findall(r"\['([^']+)'", _бл), [w for w in PL.ПРИКРАСИ_БАЖАННЯ if w != "інші"]
print("плитки показу %s + СТИЛІСТКА_КЛЮЧ == канон %s: %s" % (_жс, _кан, _жс == _кан))
assert _жс == _кан and "СТИЛІСТКА_КЛЮЧ" in _бл and "'сц-прикраси'" in _пок, "рядок розійшовся з каноном"
