# -*- coding: utf-8 -*-
"""Рядок 120: ручний рядок «Прикраси» — шість слів жінки. ДО: рядка в показі не було
(`grep прикраси показ.html` = 0), поле паспорта задавалось ЛИШЕ словами в розмові.
ПІСЛЯ: кожне слово плитки їде тим самим ключем `сценарій.прикраси` — тут перевіряємо,
що лягло в паспорт, що дістав композитор (клас металу або чесне «нема входу») і що
каже суд. Запуск із теки `джерела`: python3 проби/prykrasy_riad_120.py"""
import collections, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, pipeline as PL, feed as Ф, суд_блиск as СБ, композитор_слоти as КС

вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["каталог"] = Ф.каталог_на_диску("каталог_brief.xml")
сц = dict(нагода="побачення", місце="ресторан_районний", година=19, темп_c=12)
F = B._збірка(вх)[0]
E = [dict(річ="сережки-1", слот="сережки", метал="золото", near=0.9, площа=0.01, lab=(75.0, 5.0, 30.0))]
def пул(пасп):
    """(ювелірних у пулі, слотів, скільки з ПЕРШИХ трьох у слоті — без слова металу)."""
    r = json.loads(B.виклик("запити", json.dumps(dict(вх, сценарій=dict(сц), паспорт=пасп), ensure_ascii=False)))
    за_ід = {c.get("id"): c for c in B.каталог_останнього_пакета()}
    ю = {с: v for с, v in r["кандидати"].items() if с in Ф._МЕТАЛ_СЛОТИ}
    чоло = sum(1 for v in ю.values() for x in v[:3] if not (за_ід.get(x["id"]) or {}).get("метал"))
    return sum(map(len, ю.values())), len(ю), чоло
# шість слів рядка + «інші» (старе значення: ЖОДЕН збережений паспорт не має зламатись)
for слово in ("золото", "срібло", "перли", "етно", "без прикрас", "хай обере стилістка", "інші"):
    від_моделі = "невідомо" if слово == "хай обере стилістка" else слово
    п = PL.паспорт_з_json(json.dumps(dict(подія="побачення", нагода="побачення", прикраси=від_моделі),
                                     ensure_ascii=False), сц, "побачення")
    клас = КС._МЕТАЛ_КЛАС_БАЖАННЯ.get(п["прикраси"]) or ("нема входу: " + КС._БЕЗ_КЛАСУ_МЕТАЛУ[п["прикраси"]]
        if п["прикраси"] in КС._БЕЗ_КЛАСУ_МЕТАЛУ else "слот знято" if п["прикраси"] == "без прикрас" else "—")
    n, слотів, чоло = пул(п)
    зн = СБ.метали(E, F, драп=dict(метал="срібло"), прикраси=п.get("прикраси"))
    print("рядок «%-20s» → паспорт=%-12s · композитор: %-52s · пул: %2d у %d слотах, без металу в чолі %2d · суд: %s"
          % (слово, п["прикраси"], клас[:52], n, слотів, чоло,
             "; ".join("%s %s %.2f" % (z["правило"], z.get("регістр"), z["сила_нп"]) for z in зн) or "мовчить"))
    assert п["прикраси"] == (від_моделі if від_моделі != "невідомо" else "невідомо"), п["прикраси"]
    if слово == "без прикрас": assert n == 0 and слотів == 0, "«без прикрас» мусить прибрати прикраси з пулу"
    if слово == "хай обере стилістка": assert п["прикраси"] == "невідомо" and n > 0, "свідомий вибір → «невідомо» в паспорті"
print("показ пам'ятає свідомий вибір окремо від порожнечі:",
      "сц-прикраси=стилістка" in open("показ.html", encoding="utf-8").read().replace("'", "") or
      "СТИЛІСТКА_КЛЮЧ" in open("показ.html", encoding="utf-8").read())
