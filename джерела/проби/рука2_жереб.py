"""Р2-2в (рядок 550): скільки разів кожна з 13 тем руки 2 випадає жеребом. 3 сценарії × сіди 3–5 —
справжній `запити` на каталог_повний; і на тих самих входах (`with_input`, `acts`) — 100 сідів жеребу,
бо випадання залежить від сіда лише через монетку. Друкує: тему, скільки з 9 прогонів, частку на 100×3.
Запуск: cd джерела && python3 проби/рука2_жереб.py"""
import os, sys, json, re, collections
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge as B, правило_руки2 as ПР2
СЦ = {"office": dict(нагода="робота", місце="офіс", година=9, темп_c=18, дрес_код="business_casual"),
      "date": dict(нагода="побачення", місце="ресторан", година=20, темп_c=5, опади="дощ", тривалість_год=4),
      "wedding": dict(нагода="весілля_гість", місце="ресторан", година=16, темп_c=24, тривалість_год=8)}
вх0 = json.load(open("стенд_вх.json")); прогони, сто = collections.Counter(), collections.Counter()
поле = lambda р, к: (re.search(к + r"=([^ ·]+)", р) or [None, ""])[1]
for ім, сц in СЦ.items():
    for сід in (3, 4, 5):
        з = json.loads(B.виклик("запити", json.dumps(dict(вх0, каталог="каталог_повний.xml", сід=сід, сценарій=сц),
                                                      ensure_ascii=False)))
        п = з["поломка"]; р = п["що_змінено"]; прогони[п["тема"]] += 1
        дост = set(поле(р, "with_input").split(",")); діє = {a.split(":")[0]: a.split(":")[1].split("+")
                                                          for a in поле(р, "acts").split(",") if ":" in a}
        print("%-8s сід %d → %-10s %-14s pair=%s · with_input %d · acts %s" % (ім, сід, п["правило"], п["тема"],
              поле(р, "pair"), len(дост), поле(р, "acts")))
        if сід == 3:   # той самий вхід — монетка на 100 сідів (вхід і дія від сіда не залежать: пакет той самий)
            стар = ПР2.вхід; ПР2.вхід = lambda з, d, п=None: (з["ід"] in дост, None if з["ід"] in дост else "x")
            for с in range(100):
                сто[ПР2.жереб(dict(сід=с), None, діє=діє)[0]["тема"]] += 1
            ПР2.вхід = стар
print("тема           прогонів з 9 · частка на 300 сідах (3 сценарії × 100)")
for з in ПР2.ПЕРЕЛІК:
    print("%-14s %d · %4.1f%%" % (з["тема"], прогони[з["тема"]], сто[з["тема"]] / 3.0))
print("тем, що не випали жодного разу на 300: %d" % sum(1 for з in ПР2.ПЕРЕЛІК if not сто[з["тема"]]))
