# -*- coding: utf-8 -*-
"""Автоогляд Codex на #676 (4): суд K-OUT-02 (`верхнє_довжина.довжина`) виходив на `if not рівень` раніше,
ніж питав виміряне `нижче_коліна`, тож верхня річ з виміром довжини виробу й без слова довжини (край між
зонами — крамниця слова не дала) не діставала K-OUT-02, хоча пул (`ранг_пулу` через `нижче_коліна`) її
вже ранжував. Друкує знахідки довжини на тілі 154 см для чотирьох речей.
Після рішення менеджера 06.11 «факт замість межі» (ч15): вимір без слова бока проти коліна не називає —
поділ і коліно на її тілі — рівні шаблону без похибки, — тож суд пише K-OUT-02 «утримано» (факт моделі,
`outer_length_vs_knee_not_judged`), а не вирок; слово крамниці судить, як і раніше.
Запуск: cd джерела && python3 проби/k_out_02_вимір_без_слова.py"""
import os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import fit as ПС, композитор_річ as КР, верхнє_довжина as ВД
Т = ПС.тіло(154, dict(плечі=90, груди=84, талія=64, стегна=88))
плечі = Т["висоти"]["лінія_плеча"]
ц, рз = КР.висота_рівня("коліно", Т["висоти"])
def річ(**к):
    return dict(dict(id="п-1", слот="верхній_шар", тип_верхнього="пальто", назва="пальто"), **к)
def вимір(низ):
    return річ(довжина_виробу_см=round(плечі - низ, 1), довжина_виробу_точка="лінія_плеча", край_джерело="виріб")
РЕЧІ = (("вимір нижче коліна, слова нема", вимір(ц - (рз or 0) - 6), "утримано"),
        ("вимір вище коліна, слова нема", вимір(ц + 15), "утримано"),
        ("слово «литка», виміру нема (контроль)", річ(довжина_рівень="литка"), "default"),
        ("слово «стегно», виміру нема (контроль)", річ(довжина_рівень="стегно"), None))
вада = 0
for підпис, р, треба in РЕЧІ:
    зн = ВД.довжина([р], Т)
    є = next((з["сила"] for з in зн if з.get("правило") == "K-OUT-02"), None)
    вада += є != треба
    print("%-40s нижче_коліна=%s → K-OUT-02 %s (треба %s) · %s" % (підпис, ВД.нижче_коліна(р, Т["висоти"]),
          є, треба, [з.get("правило") for з in зн]))
print("ВАДА: K-OUT-02 на виміряній довжині без слова — не факт моделі «утримано»" if вада else
      "OK: суд K-OUT-02 на виміряній довжині без слова — факт моделі, на слові — вирок")
sys.exit(1 if вада else 0)
