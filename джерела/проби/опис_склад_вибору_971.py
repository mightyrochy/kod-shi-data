"""ВИБІР-2 (рядок 971): опис судиться над тим самим складом, який прийняв вибір.

ПЕР-536 (робота, рука 2): вибір прийняв «#208·12/низ» + окремий верх (половина комплекту,
оголошено СВІДОМО), а виклик опису йшов лише з `ід` — комплект судився цілим, останній
вердикт руки казав `слот_двічі`, і звірка стенда «на картку йде лише прийнятий образ»
червоніла. Друкує ФАКТ: вибір → опис без `частини`/`свідомі_картки` (як доти) і з ними
(як тепер шле показ). Запуск із теки `джерела`: PYTHONPATH=. python3 проби/опис_склад_вибору_971.py
"""
import json
import bridge as B

d0 = dict(json.load(open("стенд_вх.json")), рука="2", випадок="робочий день в офісі",
          сценарій=dict(нагода="робота", місце="офіс", година=9, темп_c=18))
міст = lambda **kw: json.loads(B.виклик("від_моделі", json.dumps(dict(d0, **kw), ensure_ascii=False)))
п = json.loads(B.виклик("запити", json.dumps(d0, ensure_ascii=False)))["пакети"]["2"]["пул"]
н = lambda с, k: п[с][k % len(п[с])]["н"]
образи = [dict(ід="о%d" % (k + 1), підпис="o%d" % k,
               речі=[н("комплект", k) + "/низ", н("верх", k), н("взуття", k), н("сумка", k), н("сережки", k)],
               свідомо=[dict(річ=н("комплект", k) + "/низ", чому="only the bottom half of the set is taken")])
          for k in range(5)]
в2 = міст(ітерація=2, текст_моделі=json.dumps(dict(версія="1", образи=образи), ensure_ascii=False))
в3 = міст(ітерація=2, відповідь="ВИБІР_V1", вибір_над=в2["вибір_над"],
          текст_моделі=json.dumps(dict(версія="1", обрано="о1", чому="her day")))
пв = в3["повнота"]
print("вибір: прийнято=%s · частини=%s · оголошень=%d" % (пв["повний"], пв["частини"], len(пв.get("свідомі") or [])))
опис = json.dumps(dict(версія="1", текст="Опис образу."), ensure_ascii=False)
for як, дод in (("як доти (лише ід)", {}),
                ("як тепер (+частини, +свідомі_картки)", dict(частини=пв["частини"], свідомі_картки=пв.get("свідомі")))):
    в4 = міст(ітерація=2, відповідь="ОПИС_ВІДПОВІДЬ_V1", ід=пв["ід"], текст_моделі=опис, **дод)
    бл = [б["код"] for о in (в4.get("вердикт") or {}).get("образи") or []
          for б in ((о.get("структура") or {}).get("блокери") or [])]
    print("опис %s: блокери=%s · повний=%s · свідомі=%d · знахідок_свідомих=%d" % (
        як, бл or "жодного", (в4.get("повнота") or {}).get("повний"), len(в4.get("свідомі") or []),
        sum(1 for z in в4.get("знахідки") or [] if z.get("свідомий"))))
