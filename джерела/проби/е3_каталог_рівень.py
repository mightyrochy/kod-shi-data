"""Друкує відбір і суд рівня події на всьому каталозі; аргумент — тека модулів ДО."""
from collections import Counter
from pathlib import Path
import os, sys
ТУТ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ТУТ))
if len(sys.argv) > 1: sys.path.insert(0, sys.argv[1])
os.chdir(ТУТ)
import feed as Ф, композитор_придатні as П, суд_від_моделі as С
каталог = Ф.база_прогону(Ф.каталог_на_диску("каталог_повний.xml"), 0)["каталог"]
за_ід = {р["id"]: р for р in каталог}
print("Каталог:", len(каталог), "речей")
for рівень in (4, 6, 7, 9):
    сцена = dict(ошатність=[рівень, рівень], _ошатність=[рівень, рівень], пора="день")
    лиш, геть, смуга = П.поза_сценою(каталог, сцена)
    знахідки = С.нижче_смуги_образу(list(за_ід), за_ід, сцена)
    дубль = С.доповнення_судді(каталог, сцена)
    print("Рівень", рівень, "смуга", смуга, "лишились", len(лиш), "геть", len(геть),
          "нижче з позначкою", sum(bool(р.get("_нижче_смуги")) for р in лиш),
          "суд", dict(Counter((з["правило"], з["сила"]) for з in знахідки)),
          "чужа сумка під K-KOH-08", sum(з["правило"] == "K-KOH-08" for з in дубль))
