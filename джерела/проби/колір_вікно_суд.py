"""КОЛІР-ВІКНО-СУД (рядки 3080–3083): суд кольору-вікна — «так / ні / невідомо», а не центр вікна. Продуктовий ендпойнт
`від_моделі` (заглушка стенда, `pal_вердикт.стенд`) на 60 випадкових образах (сід 11) з кандидатів стенда, двічі: намір
conventional і statement. Лічба «правило:сила» і «правило:без_входу» правил рядків (K-PAL-03/09/14/10/02/13/07/08, K-INT-04, K-CRA-02, R-COL-16,
K-COL-06); «без_входу» — виклик `без_входу_кольору` правила на образі (поле `колір_не_вимір`). З `-д` — підпис образів зі знахідками (diff ДО/ПІСЛЯ).
Запуск із джерела/: python3 проби/колір_вікно_суд.py [-д]"""
import random, sys, collections as K; sys.path.insert(0, "."); sys.path.insert(0, "проби")
import pal_вердикт as ПВ, колір_річ as КР, колір_образу as КО, колір_нейтралі as КН
_б, Б = КР.без_входу_кольору, set()   # «без входу» правила за образ (запис «питання» до вердикту не їде)
def _лов(правило, *a, **k): Б.add(правило); return _б(правило, *a, **k)
for _м in (КР, КО, КН): _м.без_входу_кольору = _лов
ПР = ("K-PAL-03", "K-PAL-09", "K-PAL-14", "K-PAL-10", "K-PAL-02", "K-PAL-13", "K-PAL-07", "K-PAL-08",
      "K-INT-04", "K-CRA-02", "R-COL-16", "K-COL-06")
СЛОТИ = ("верх", "низ", "сукня", "верхній_шар", "взуття", "сумка", "шарф", "сережки", "намисто"); Л = K.Counter(); Д = []
for намір in ("conventional", "statement"):
    вх, r, кат, _ = ПВ.стенд(гілка=0, намір=намір); к, rnd = r["кандидати"], random.Random(11)
    for n in range(60):
        ід = [rnd.choice(к[с])["id"] for с in СЛОТИ if к.get(с) and с not in (("верх", "низ") if n % 2 else ("сукня",))
              and (с in ("верх", "низ", "сукня", "взуття") or rnd.random() < 0.6)]
        Б.clear(); зн, _ = ПВ.знахідки(вх, ід)
        п = sorted(["%s:%s" % (z.get("правило"), z.get("сила")) for z in зн if z.get("правило") in ПР]
                   + ["%s:без_входу" % x for x in Б if x in ПР])
        for x in п: Л[x] += 1
        Л["образів"] += 1
        Д.append("%s#%02d %s | %s" % (намір[:4], n, " ".join(п), " · ".join("%s%s" % ((кат.get(x) or {}).get("колір_ім") or "?", "~" if КР.не_вимір(кат.get(x) or {}) else "") for x in ід)))
for к_, v in sorted(Л.items()): print("  %-22s %4d" % (к_, v))
if "-д" in sys.argv: print("\n".join(Д))
