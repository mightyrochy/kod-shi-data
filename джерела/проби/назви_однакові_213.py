"""Рядок 213: назви показу, що не відрізняють речей однієї крамниці. Запуск: cd джерела && python3 проби/назви_однакові_213.py
Мірка: назва показу ≤3 слів і однакова в крамниці ≥10 разів; скільки таких назв дала б `скласти(тип, слот, колір)`, кількість різних назв."""
import collections, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, назва_речі as НР
оф = feed.читати_yml(feed.каталог_на_диску())[0]
НИЖЧЕ_СЛІВ, ВІД_РАЗІВ = 3, 10
показ = {o["id"]: НР.на_картці(o) for o in оф}
група = collections.defaultdict(list)
for o in оф:
    група[(o["магазин"], показ[o["id"]].lower())].append(o)
важкі = {к: v for к, v in група.items() if len(v) >= ВІД_РАЗІВ and len(к[1].split()) <= НИЖЧЕ_СЛІВ}
зачеплено = sum(len(v) for v in важкі.values())
print("ФАКТ · назв показу ≤%d слів, однакових у крамниці ≥%d разів: %d назв у %d крамницях, речей %d з %d (%.1f%%)"
      % (НИЖЧЕ_СЛІВ, ВІД_РАЗІВ, len(важкі), len({к[0] for к in важкі}), зачеплено, len(оф), 100.0 * зачеплено / len(оф)))
по_крамниці = collections.Counter()
for (кр, _), v in важкі.items():
    по_крамниці[кр] += len(v)
print("ФАКТ · по крамницях: %s" % dict(по_крамниці.most_common(8)))
складено = collections.defaultdict(set)
for (кр, н), v in важкі.items():
    for o in v:
        п = o["параметри"]
        з = НР.скласти(тип=п.get("тип"), слот=п.get("слот") or o.get("категорія"), колір=o.get("колір_назва") or п.get("колір"),
                       довжина=п.get("довжина") or п.get("довжина_рівень"))
        складено[(кр, н)].add(з)
for (кр, н), v in sorted(важкі.items(), key=lambda x: -len(x[1]))[:8]:
    print("ФАКТ · %s «%s» ×%d → `скласти` дає %d різних: %s" % (кр, н, len(v), len(складено[(кр, н)]), sorted(x or "—" for x in складено[(кр, н)])[:4]))
