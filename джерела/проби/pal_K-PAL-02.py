# -*- coding: utf-8 -*-
"""K-PAL-02 (перегук рис: очі першими) — ранг риси нарешті щось вирішує.

Корпус (тема-2:1848): «повторити колір очей як акцент … завжди доступний, ПЕРШИЙ
за порядком» (R-COL-17; Perrett 2023: одяг обирають до райдужки, 200 учасників).
Код ставив рядкам запиту `ранг_риси` (очі 1) і сортував ним САМІ РЯДКИ; добір
читав рядки множиною, тож ранг не міняв нічого.
ПІСЛЯ — два яруси: у ПУЛІ ранг став другим членом ключа сортування кандидатів
(після колірної відстані, перед реєстром: рухає РІВНЕ); у ВЕРДИКТІ слот, якому
схема дала роль акценту, судиться на належність сім'ї очей.
Запуск із теки `джерела`: `python3 проби/pal_K-PAL-02.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import pipeline as PL, palettes as PAL

вх, r, кат, спец = ПВ.стенд(гілка=0, самозвіт={"метал": "золото"})
_, запити = __import__("bridge").спец_останнього_пакета()
очі = ((спец["палітра_практична"]["вікна"].get("сім_ї") or {}).get("очі") or [])
у_очах = lambda h: any((a[0] - 10 <= h <= a[1] + 10) for a in очі)
акц = [с for с, v in (спец.get("слоти") or {}).items()
       if isinstance(v, dict) and v.get("роль") == "акцент"]
кольоровий = lambda L, C, h, з, с: (not PL._нейтральний_тон(h, C, L)
                                    and not PAL.метал_речі(з["lab"], с))
свої = чужі = 0
for с in акц:
    for x in (r["кандидати"].get(с) or []):
        L, C, h = ПВ.lch(кат, x["id"])
        if L is None or not кольоровий(L, C, h, кат[x["id"]], с): continue
        свої, чужі = (свої + 1, чужі) if у_очах(h) else (свої, чужі + 1)
print("ПУЛ · рядків з рангом 1 (сім'я очей) %d із %d · у %d акцентних слотах кольорових "
      "речей: із сім'ї очей %d, чужих %d"
      % (sum(1 for q in запити if int(q.get("ранг_риси") or 9) == 1), len(запити), len(акц), свої, чужі))

# ВЕРДИКТ. Чужий акцент береться з КАТАЛОГУ, бо в пулі його після правки вікон
# майже нема — а модель назвати таку річ може, і судити її код мусить.
чужа = ПВ.з_каталогу(кат, акц[0] if акц else "сумка",
                     lambda L, C, h, з: кольоровий(L, C, h, з, акц[0]) and not у_очах(h))
решта = [ПВ.взяти(r, кат, с, lambda *a: True) for с in ("верх", "низ", "взуття")]
print("сім'я очей: %s · чужий акцент у каталозі: %s"
      % ("; ".join("%.0f–%.0f°" % (a[0], a[1]) for a in очі), (чужа or {}).get("назва", "нема")[:34]))
зн, _ = ПВ.знахідки(вх, [x["id"] for x in [чужа] + [y for y in решта if y] if x][:4])
print("ФАКТ · K-PAL-02: %s" % ПВ.рядок(зн, "K-PAL-02"))
assert next((x for x in зн if x.get("правило") == "K-PAL-02"), None), "акцент не від очей, а правило мовчить"
