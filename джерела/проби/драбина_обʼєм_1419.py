"""Рядок 1419: K-OUT-06 «не налізе поверх обʼємного» — скільки речей торса каталог_повний стають
«обʼємними» під приталеним пальтом (strong) і скільки дістають «питання», за класом речі: светр-клас,
верхній одяг, інше (футболка, блуза, сорочка, боді…). Моделі не кличе.
Запуск: python3 джерела/проби/драбина_обʼєм_1419.py"""
import collections, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import фід_каталог as ФК, верхнє_стан as ВС                                   # noqa: E401,E402
к = [r for r in ФК._прочитати_каталог(ФК.каталог_на_диску(), ліміт_фото=0)["каталог"]
     if r.get("слот") in ("верх", "сукня", "комплект", "верхній_шар") and not ВС._структурний(r)]
пальто = {"id": "п", "слот": "верхній_шар", "тип": "пальто", "крій": "fitted", "назва": "Пальто"}
def клас(r):
    if r.get("тип") in ("светр", "кардиган", "худі", "кніт"): return "светр-клас"
    if r.get("слот") == "верхній_шар" or r.get("тип") in ВС._ВЕРХНІЙ_ОДЯГ: return "верхній одяг"
    return "інше"
лік, прикл = collections.Counter(), collections.defaultdict(list)
for r in к:
    for z in ВС.драбина_шарів([r, пальто]):
        if z.get("правило") == "K-OUT-06" and "горловин" not in str(z.get("суть")):
            ключ = (z.get("сила"), клас(r)); лік[ключ] += 1
            прикл[ключ].append("%s·%s" % (r.get("тип"), r.get("крій")))
print("речей торса (не структурних): %d" % len(к))
for (сила, кл), n in sorted(лік.items()):
    print("  %-8s %-13s %4d  напр.: %s" % (сила, кл, n, ", ".join(sorted(set(прикл[(сила, кл)]))[:6])))
