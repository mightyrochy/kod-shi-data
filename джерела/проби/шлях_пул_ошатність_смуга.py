"""Розбір 3/8: скільком смугам ошатності підлягає ОДИН прогін.

Прогін власника 25.09 (розклад 4123): нагода «щоденне», місце «театр», година 18,
дрес-код і ошатність — null. До читачів смуги доїжджають УСІЧЕНІ копії сцени, і
кожна дає свою шкалу: у файлі пул судив 4–6 (сцена без години), а вердикт обох її
речей з фото — 3–4 (сцена без місця), тож річ ошатності 6 водночас «придатна» для
пулу й «занадто ошатна» для суду. Проба питає читачів тими копіями, що в файлі.
Вада: різних смуг > 1. Після правки шов кладе смугу в сцену полем, і копія її везе.
Прогін: python3 проби/шлях_пул_ошатність_смуга.py
"""
import json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ)
os.chdir(ТУТ)
import формальність as Ф, річ_з_фото as РФ, сценарій as СЦ, композитор_придатні as КП
ФАЙЛ = os.path.join(os.path.dirname(ТУТ), "аудит", "тести", "власник_2026-09-25",
                    "verdykty-0phxvk-2026-09-25-2012.json")
сп = [p for p in json.load(open(ФАЙЛ, encoding="utf-8"))["прогони"]
      if p["спільне"].get("розклад") == "4123"][0]["спільне"]
сцен, _ = СЦ.з_показу((сп.get("вхід_прогону") or {}).get("сценарій") or {}, сп["паспорт"])
ШТАМП = getattr(Ф, "ШТАМП_СМУГИ", "_смуга_ошатності")   # на коді до правки штампа нема
_ш = getattr(Ф, "смуга_ошатності", lambda _с: None)(сцен)
if _ш:
    сцен[ШТАМП] = [_ш[0], _ш[1]]                  # шов (`міст_пакет`) кладе це полем
print("сцена прогону: %s | штамп шва: %s" % (json.dumps({к: сцен.get(к) for к in
      ("нагода", "місце", "година", "дрес_код", "ошатність")}, ensure_ascii=False),
      сцен.get(ШТАМП) or "— нема"))
без = lambda *кл: {k: v for k, v in сцен.items() if k not in кл}
смуги = {"добір пулу, копія без години": КП.смуга_нагоди(без("година")),
         "суд її речі, копія без місця": РФ._шкала_нагоди(без("місце"))[:2],
         "повна сцена": КП.смуга_нагоди(сцен)}
for хто, с in смуги.items():
    print("  %-30s → смуга %s" % (хто, tuple(float(x) for x in с)))
різних = {tuple(float(x) for x in с) for с in смуги.values()}
print("РІЗНИХ СМУГ НА ОДНУ СЦЕНУ: %d %s" % (len(різних), sorted(різних)))
ноти = ((сп.get("етапи") or {}).get("прогін") or {}).get("ноти_слотів") or {}
for с, н in list(ноти.items())[:2]:
    print("у файлі, пул слот %-12s %s" % (с, н[:80]))
for р in (сп["паспорт"].get("речі_з_фото") or []):
    в = json.loads(р["вердикт"]) if isinstance(р.get("вердикт"), str) else (р.get("вердикт") or {})
    print("у файлі, її річ %s ошатність %s → %s" % (р["ід"], р.get("ошатність"), str(в.get("рядок"))[:66]))
