"""Розбір 3/8: скільком смугам ошатності підлягає ОДИН прогін.

Прогін власника 25.09 (розклад 4123): у полях показу нагода «щоденне», місце
«театр», година 18, дрес-код і ошатність — null; обидві її речі з фото мають
ошатність 6 і вердикт «для цієї нагоди річ занадто ошатна». Проба питає
`формальність.сценарій` тими самими полями в різних наборах і показує, яку смугу
дає кожен, та якою смугою судив пул і якою — вердикт її речі.
Прогін: python3 проби/шлях_пул_ошатність_смуга.py
"""
import json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ТУТ)
os.chdir(ТУТ)
import формальність as Ф, річ_з_фото as РФ
ПОЛЯ = dict(нагода="щоденне", місце="театр", година=18, темп_c=10)
for набір in (("нагода",), ("місце",), ("нагода", "місце"), ("нагода", "місце", "година", "темп_c")):
    п = {к: ПОЛЯ[к] for к in набір}
    р = Ф.сценарій(місце=п.get("місце"), код=Ф.код_дрес(None), година=п.get("година"),
                   нагода=п.get("нагода"), темп_c=п.get("темп_c"))
    print("поля %-38s → смуга %s" % (", ".join(набір), tuple(р["діапазон"])))
print("дрес-код smart_casual (його у вхід_прогону НЕМА) → смуга %s"
      % (Ф.сценарій(місце="театр", код=Ф.код_дрес("smart_casual"), година=18,
                    нагода="щоденне", темп_c=10)["діапазон"],))
print("допуск річ_з_фото.ОШАТНІСТЬ_ДОПУСК = %s" % РФ.ОШАТНІСТЬ_ДОПУСК)
ФАЙЛ = os.path.join(os.path.dirname(ТУТ), "аудит", "тести", "власник_2026-09-25",
                    "verdykty-0phxvk-2026-09-25-2012.json")
пр = [p for p in json.load(open(ФАЙЛ, encoding="utf-8"))["прогони"]
      if p["спільне"].get("розклад") == "4123"][0]
ноти = ((пр["спільне"].get("етапи") or {}).get("прогін") or {}).get("ноти_слотів") or {}
for с, н in ноти.items():
    print("пул, слот %-12s %s" % (с, н[:110]))
for р in (пр["спільне"]["паспорт"].get("речі_з_фото") or []):
    в = json.loads(р["вердикт"]) if isinstance(р.get("вердикт"), str) else (р.get("вердикт") or {})
    print("її річ %s ошатність %s → %s" % (р["ід"], р.get("ошатність"), str(в.get("рядок"))[:95]))
for ош in (3, 4, 6):
    сп = [лхз for лхз in (РФ._шкала_нагоди(dict(нагода="щоденне")), РФ._шкала_нагоди(dict(ошатність=[4, 6])))]
    print("ошатність %d: промах у смузі %s = %s, у смузі %s = %s"
          % (ош, сп[0][:2], max(0, ош - сп[0][1] - РФ.ОШАТНІСТЬ_ДОПУСК),
             сп[1][:2], max(0, ош - сп[1][1] - РФ.ОШАТНІСТЬ_ДОПУСК)))
