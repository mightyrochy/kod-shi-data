# -*- coding: utf-8 -*-
"""Поле `корінь=` рядка дошки: обов'язкове від межі, звіряється з паспортами, заміна його не стирає (рядок 14291)."""
import sys, tempfile
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'прилади'))
import згорнути_дошку as згортання
from дошка_поля import ПЕРШИЙ_НОМЕР_КОРЕНЯ as Н
from рядки_корінь_нуль import корені_рядка
поля = lambda к='': '<!-- дошка: дата=2026-11-08; рід=мірило; попередник=ні; механізм=нема-мірила' + (f'; корінь={к}' if к else '') + ' -->'
Р = lambda н, к='', стан='**ВІДКРИТО**': f'| {н} | проба · факт {поля(к)} | низька | {стан} | доказ · виявлено: проба; внесено: давнє |'
with tempfile.TemporaryDirectory() as тека:
    т = Path(тека); (т / 'фрагменти').mkdir(); (т / 'корені').mkdir()
    (т / 'корені' / 'Е2-межі.md').write_text('# Корінь Е2-межі: …\n', encoding='utf-8')
    (т / 'корені' / 'Е2-межі-перелік.md').write_text('# Перелік місць\n', encoding='utf-8')
    згортання.КОРІНЬ, згортання.ДОШКА, згортання.ТЕКА, згортання.КОРЕНІ = тека, str(т / 'дошка.md'), str(т / 'фрагменти'), str(т / 'корені')
    дошка, фрагмент = Path(згортання.ДОШКА), т / 'фрагменти' / 'проба.md'
    дошка.write_text(Р(Н - 1) + '\n' + Р(Н + 1, 'Е2-межі') + '\n', encoding='utf-8')
    помилки = lambda текст: (фрагмент.write_text(текст, encoding='utf-8'), згортання.згорнути(True)[1])[1]
    assert any('поле корінь: відсутнє' in п for п in помилки(Р(Н))), 'від межі без кореня'
    assert not помилки(Р(Н - 2)), 'до межі без кореня'
    for к in ('Е2-межі', 'жоден'):
        assert not помилки(Р(Н, к)), к
    for к in ('Е2-межі-перелік', 'Е9-нема', 'Е2-межі+Е2-межі', 'жоден+Е2-межі'):
        assert any('поле корінь: очікується' in п for п in помилки(Р(Н, к))), к
    assert not помилки('заміна ' + Р(Н - 1, 'жоден')), 'заміна додає корінь старому рядку'
    assert any('зберігати корінь' in п for п in помилки('заміна ' + Р(Н + 1))), 'заміна стирає корінь'
    assert not помилки('заміна ' + Р(Н + 1, 'жоден')), 'заміна міняє корінь'
    імена = ['Е2-межі', 'Е2-вікно']
    assert корені_рядка(Р(1, 'жоден') + ' корінь Е2-вікно', імена) == [], 'поле старше за прозу'
    assert корені_рядка(Р(1, 'Е2-межі'), імена) == ['Е2-межі'] and корені_рядка(Р(1) + ' корінь Е2-вікно', імена) == ['Е2-вікно']
print(f'корінь рядка: від {Н} обов\'язковий; паспорт «# Корінь» прийнято, перелік і вигадане — ні; заміна додає й міняє, не стирає; поле старше за прозу')
