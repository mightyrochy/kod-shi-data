"""Ділянка 8: КУДИ ЙДЕ ЇЇ ПИТАННЯ про образ з фото. Мовний шар увімкнено за замовчуванням
(`МОДЕЛЬ_МОВИ_П` = модель продукту), і `розмоваШаромП` віддає питання жінки `помічникП` —
моделі-ДОВІДЦІ про застосунок. Друкує розмір і склад того, що помічниця бачить, і перелік
входів оцінки образу, яких у її промпті нема.
Запуск із `джерела`: python3 проби/шлях_оцінка_помічниця.py"""
import sys, re; sys.path.insert(0, '.')
T = open('показ.html', encoding='utf-8').read()
РЯД = lambda взір: T[:re.search(взір, T).start()].count('\n') + 1
print('шар мови вмикається сам: показ.html:%d — %s'
      % (РЯД(r"return БЕЗ_ШАРУ_МОВИ_П\.test"), "БЕЗ_ШАРУ_МОВИ_П.test(з) ? null : (з.trim() || МОДЕЛЬ_П)"))
print('питання жінки → помічниця: показ.html:%d «const питання = (пер.внутрішня.question || {}).free_text»'
      % РЯД(r"const питання = \(пер\.внутрішня\.question"))
print('помічниця = %s' % T[re.search(r'const ШІ_ПРОМПТ_ПОМІЧНИКА', T).start():][:118].split("= ")[1])
довідка = re.search(r'const ШІ_ДОВІДКА = `(.*?)`;', T, re.S).group(1)
промпт = re.sub(r"\s*\+\s*'|'", '', re.search(r'const ШІ_ПРОМПТ_ПОМІЧНИКА = (.*?);\n\n', T, re.S).group(1))
стан = re.search(r"function станДляШі\(\)\{(.*?)\n\}", T, re.S).group(1)
поля_стану = [п.strip() for п in re.findall(r"push\('· ([^:']+)", стан)]
print('що їде в помічницю: промпт %d симв. + ДОВІДКА ПРО ЗАСТОСУНОК %d симв. + СТАН %d полів (%s)'
      ' + останні 8 реплік по ≤400 симв. + її питання (перекладене)'
      % (len(промпт), len(довідка), len(поля_стану), ', '.join(поля_стану)))
print('  довідка радить тиснути «Зібрати образи» %d рази й називає кнопки %d разів'
      % (довідка.count('Зібрати образи'), довідка.count('кнопк')))
print('  промпт помічниці наказує: %s'
      % '; '.join(ф.strip() for ф in промпт.split('. ') if ф.strip().startswith(('Відповідай на її питання',
                                                                                'Не вигадуй', 'Не називай'))))
БРАК = [('саме фото її образу', r'модельП\(промпт\)'), ('речі з фото (назва, слот, колір)', 'речі_з_фото'),
        ('вердикт коду над річчю', 'вердикт_коду'), ('її палітра числами', 'палітра_практична'),
        ('суд образу (K-COL-*, K-CLR-02)', 'перевірити_образ')]
пом = T[re.search(r'async function помічникП', T).start():][:900]
print('чого в помічниці НЕМА: %s' % '; '.join(н for н, к in БРАК if к not in пом))
print('  → вона відповідає про ЗАСТОСУНОК, бо іншого входу їй не дали; фото вона не бачить взагалі')
