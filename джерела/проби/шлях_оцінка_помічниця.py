"""Ділянка 8: КУДИ ЙДЕ ЇЇ ПИТАННЯ про образ з фото. Мовний шар увімкнено за замовчуванням
(`МОДЕЛЬ_МОВИ_П` = модель продукту), і `розмоваШаромП` віддає питання жінки `помічникП` —
моделі-ДОВІДЦІ про застосунок. Друкує розмір і склад того, що помічниця бачить, і перелік
входів оцінки образу, яких у її промпті нема.
П-4 (27.09.2026): промпт помічниці — оголошення збирача англійською (`міст_помічниця.ДОВІДКА`),
довідка — `ШІ_ДОВІДКА` англійською з написами екрана, стан — фактами (`станДляШі`).
Запуск із `джерела`: python3 проби/шлях_оцінка_помічниця.py"""
import sys, re; sys.path.insert(0, '.')
import міст_помічниця as МП
T = open('показ.html', encoding='utf-8').read()
РЯД = lambda взір: T[:re.search(взір, T).start()].count('\n') + 1
print('шар мови вмикається сам: показ.html:%d — %s'
      % (РЯД(r"return БЕЗ_ШАРУ_МОВИ_П\.test"), "БЕЗ_ШАРУ_МОВИ_П.test(з) ? null : (з.trim() || МОДЕЛЬ_П)"))
# М-1: питання про образ, коли речі з фото в розмові є, іде стилістці; помічниці — решта
print('питання жінки → показ.html:%d; стилістці, коли %s; інакше помічниці'
      % (РЯД(r"const питання = \(\(пер && пер\.внутрішня\.question\)"),
         "question_about === 'look' і речі_з_фото непорожні"
         if re.search(r"question_about === 'look'\s*&& \(\(ПАСПОРТ_П \|\| \{\}\)\.речі_з_фото", T)
         else "— (умови стилістки в показі нема: усе йде помічниці)"))
о = МП.ДОВІДКА
print('помічниця = %s (шаблон %s, відповідь %s)' % (о.роль, о.мова_промпту, о.відповідь_як))
довідка = re.search(r'const ШІ_ДОВІДКА = `(.*?)`;', T, re.S).group(1)
стан = re.search(r"function станДляШі\(\)\{(.*?)\n\}", T, re.S).group(1)
поля_стану = re.findall(r"(?m)^    ([а-яіїєґʼ_]+):", стан)
print('що їде в помічницю: правил %d + ДОВІДКА %d симв. (написів «…» %d) + СТАН %d полів (%s)'
      ' + останні 8 реплік по ≤400 симв. + її питання (перекладене)'
      % (len(о.правила), len(довідка), len(re.findall(r"\{[a-z_]+\}", довідка)), len(поля_стану),
         ', '.join(поля_стану)))
print('  довідка радить тиснути «Зібрати образи» %d рази' % довідка.count('{build}'))
print('  промпт помічниці наказує: %s' % '; '.join(п for п in о.правила
                                                   if п.startswith(('Answer her', 'If the answer', 'Name no'))))
БРАК = [('саме фото її образу', r'модельП\(р1\.промпт\)'), ('речі з фото (назва, слот, колір)', 'речі_з_фото'),
        ('вердикт коду над річчю', 'вердикт_коду'), ('її палітра числами', 'палітра_практична'),
        ('суд образу (K-COL-*, K-CLR-02)', 'перевірити_образ')]
пом = T[re.search(r'async function помічникП', T).start():][:900]
print('чого в помічниці НЕМА: %s' % '; '.join(н for н, к in БРАК if к not in пом))
print('  → питання про образ без речей у розмові (і будь-яке інше) вона відповідає про ЗАСТОСУНОК:'
      ' іншого входу їй не дали; фото вона не бачить взагалі')
