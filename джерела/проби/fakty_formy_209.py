# -*- coding: utf-8 -*-
"""ЗАМОВЧУВАННЯ ФОРМИ Й ПЕРЕЛІК ЗІ СХЕМИ (рядок 209, Т-3 і Т-5; прохід ноутбучної
тестувальниці 24.09, паспорти qwen3.5-9b). Шлях справжній: сценарій — такий, яким його
шле `показ.зібратиВхід` (вшиті 11:00 і 18 °C), паспорт — через `bridge.виклик("паспорт")`.
ДО — те саме без мітки форми й зі значенням `рух` як є (поведінка main). Рахуємо, скільки
НЕ ЇЇ стоїть у рядку випадку, що їде в усі 4 промпти й у шапку, і чи ціле її власне."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, паспорт_нагоди as ПН
ОФІС = dict(подія="робочий день", нагода="робота", місце="офіс_корпоративний", формат="приміщення",
            рух="сидіти | ходити", година=11, темп_c=18)
СОБАКИ = dict(подія="прогулянка", нагода="щоденне", місце="парк", формат="просто неба", рух="ходити", темп_c=18)
ВИПАДКИ = [   # (слова жінки, що повернула модель, чи рука торкалась чисел, чого НЕ має бути, що має бути)
    ("робочий день в офісі, дрес-код business casual, без підборів", ОФІС, False,
     ["11:00", "18 °C", "сидіти | ходити"], ["офіс корпоративний"]),
    ("гуляю з собаками у парку", СОБАКИ, False, ["18 °C"], ["парк", "ходити"]),
    ("прощання, надворі плюс шість", dict(ОФІС, нагода="похорон"), False, ["18 °C", "11:00"], ["6 °C"]),
    ("робочий день в офісі", ОФІС, True, [], ["11:00", "18 °C"])]   # рука сама поставила — нічого не гине
не_її, згублено, теми = [0, 0], [0, 0], []
for слова, мод, рукою, чуже, своє in ВИПАДКИ:
    форма = dict(нагода="робота", місце=None, дрес_код=None, година=11, темп_c=18.0)
    якщо_рука = dict(форма) if рукою else dict(форма, типові_поля=["година", "темп_c"])
    п = json.loads(B.виклик("паспорт", json.dumps(dict(сценарій=якщо_рука, вимоги=слова,
                            json_моделі=json.dumps(мод, ensure_ascii=False)), ensure_ascii=False)))["паспорт"]
    пдо = json.loads(B.виклик("паспорт", json.dumps(dict(сценарій=форма, вимоги=слова,
                              json_моделі=json.dumps(мод, ensure_ascii=False)), ensure_ascii=False)))["паспорт"]
    рядки = [ПН.паспорт_рядком(dict(пдо, рух=str(мод.get("рух") or пдо["рух"]).strip())), ПН.паспорт_рядком(п)]
    for i, р in enumerate(рядки):
        не_її[i] += sum(1 for c in чуже if c in р); згублено[i] += sum(1 for c in своє if c not in р)
    print("   %-34s ПІСЛЯ: %s" % (слова[:34], рядки[1][:96]))
    # наступний хід тієї самої розмови: чи спитає стилістка про градуси сама (п.9 — порада)
    сл = json.loads(B.виклик("паспорт", json.dumps(dict(сценарій=якщо_рука, вимоги=слова, паспорт=п,
                    json_моделі="{}"), ensure_ascii=False), ))["паспорт"]
    теми += [t for t in (сл.get("поради_дані") or []) if t == "температура"]
print("випадків %d · НЕ ЇЇ у рядку випадку (4 промпти + шапка): ДО %d → ПІСЛЯ %d · її власного згублено: ДО %d → ПІСЛЯ %d"
      "\n   стилістка сама питає про градуси, коли просто неба й вона їх не називала: тем «температура» %d"
      % (len(ВИПАДКИ), не_її[0], не_її[1], згублено[0], згублено[1], len(теми)))
assert (не_її[1], згублено[1]) == (0, 0), "замовчування форми чи перелік схеми досі в рядку випадку"
assert теми, "порада про температуру мовчить там, де жінка градусів не називала"
