# -*- coding: utf-8 -*-
"""ЗАМОВЧУВАННЯ ФОРМИ Й ПЕРЕЛІК ЗІ СХЕМИ (рядок 209, Т-3 і Т-5; проходи ноутбучної тестувальниці
24–25.09, qwen3.5-9b і жива gemma-4-12b). Шлях справжній: сценарій — такий, яким його шле
`показ.зібратиВхід` (вшиті 11:00 і 18 °C), паспорт — через `bridge.виклик("паспорт")`. ДО — те саме
без мітки форми й зі значенням `рух` як є (поведінка main). Рахуємо НЕ ЇЇ у двох місцях, звідки модель
це переказує жінці: рядок випадку (усі 4 промпти + шапка) і поля випадку ПАКЕТА («при 18 °C» у «день»)."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, паспорт_нагоди as ПН, пакет_моделі as ПМ
ОФІС = dict(подія="робочий день", нагода="робота", місце="офіс_корпоративний", формат="приміщення",
            рух="сидіти | ходити", година=11, темп_c=18)
СОБАКИ = dict(подія="прогулянка", нагода="щоденне", місце="парк", формат="просто неба", рух="ходити", темп_c=18)
ФОРМА = dict(нагода="робота", місце=None, дрес_код=None, година=11, темп_c=18.0)
ВИПАДКИ = [   # (слова, що повернула модель, чи рука торкалась чисел, чого НЕ має бути, що має бути)
    ("робочий день в офісі, дрес-код business casual, без підборів", ОФІС, False,
     ["11:00", "18 °C", "сидіти | ходити"], ["офіс корпоративний"]),
    ("гуляю з собаками у парку, вітер", СОБАКИ, False, ["18 °C"], ["парк", "ходити"]),
    ("прощання, надворі плюс шість", dict(ОФІС, нагода="похорон"), False, ["18 °C", "11:00"], ["6 °C"]),
    ("робочий день в офісі", ОФІС, True, [], ["11:00", "18 °C"])]   # рука сама поставила — нічого не гине
не_її, згублено, теми = [0, 0], [0, 0], []
def паспорт(сц, слова, мод, досі=None):
    д = dict(сценарій=сц, вимоги=слова, json_моделі=json.dumps(мод, ensure_ascii=False))
    return json.loads(B.виклик("паспорт", json.dumps(dict(д, паспорт=досі) if досі else д,
                                                     ensure_ascii=False)))["паспорт"]
for слова, мод, рукою, чуже, своє in ВИПАДКИ:
    як_рука = ФОРМА if рукою else dict(ФОРМА, типові_поля=["година", "темп_c"])
    п, пдо = паспорт(як_рука, слова, мод), паспорт(ФОРМА, слова, мод)
    рядки = [ПН.паспорт_рядком(dict(пдо, рух=str(мод.get("рух") or пдо["рух"]).strip())), ПН.паспорт_рядком(п)]
    не_назвала = ПН.типові_з_форми(п)      # що з чисел вона не називала — каже мітка ПІСЛЯ
    for i, (р, х) in enumerate(zip(рядки, (пдо, п))):
        в = ПМ.випадок_для_пакета(х, р, як_рука)
        не_її[i] += sum(1 for c in чуже if c in р) + sum(1 for k in не_назвала if k in в)
        згублено[i] += sum(1 for c in своє if c not in р)
    print("   %-30s ПІСЛЯ: %s" % (слова[:30], рядки[1][:92]))
    # наступний хід тієї самої розмови: чи спитає стилістка про градуси сама (п.9 — порада)
    сл = паспорт(як_рука, слова, {}, досі=п)
    теми += [t for t in (сл.get("поради_дані") or []) if t == "температура"]
print("випадків %d · НЕ ЇЇ (рядок випадку 4 промптів + поля випадку пакета): ДО %d → ПІСЛЯ %d · її власного згублено: ДО %d → ПІСЛЯ %d"
      "\n   стилістка сама питає про градуси, коли просто неба й вона їх не називала: тем «температура» %d"
      % (len(ВИПАДКИ), не_її[0], не_її[1], згублено[0], згублено[1], len(теми)))
assert (не_її[1], згублено[1]) == (0, 0), "замовчування форми чи перелік схеми досі доходять до моделі"
assert теми, "порада про температуру мовчить там, де жінка градусів не називала"
