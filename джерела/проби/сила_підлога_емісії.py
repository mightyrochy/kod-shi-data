"""Підлога позначає остаточну вагу емітента, не проміжний вимір конструктора."""
import pathlib
import sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import реєстр_сила as С


def main():
    """Не переносити підпідлогову позначку на наступну категорійну вагу."""
    з = С.зн('K-WEA-03', 'soft', 'темна річ', [], 'сонце',
             вимір=0.01, поріг=0, повна=1)
    assert 0 < з['сила_нп'] < С.підлога_нп()
    assert not з.get('під_підлогою'), 'проміжна вага позначена як остаточна'
    готова = dict(з, сила_нп=С.КАТ_У_НП[з['сила']])
    assert not С.обмежити_вагу([готова])[0].get('під_підлогою')
    assert С.обмежити_вагу([dict(з)])[0]['під_підлогою']
    print('підлога: остаточну вагу позначено, проміжна не відсіює готову знахідку')


if __name__ == '__main__':
    main()
