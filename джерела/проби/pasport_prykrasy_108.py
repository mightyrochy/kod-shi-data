# -*- coding: utf-8 -*-
"""Рядок 108: прикраси З ЦИМ образом — бажання зі слів жінки. Три фрази (золото / без прикрас /
нічого) → паспорт.прикраси, пул ювелірних слотів за металом (лічба з каталог_brief) ДО (паспорт без
поля) і ПІСЛЯ; знахідка суду K-COL-06-M, коли бажання суперечить драпіровці профілю (hint, без
вироку — R-TYP-04). Запуск із теки `джерела`: python3 проби/pasport_prykrasy_108.py"""
import collections, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bridge as B, pipeline as PL, feed as Ф, суд_блиск as СБ

вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["каталог"] = Ф.каталог_на_диску("каталог_brief.xml")
сц = dict(нагода="побачення", місце="ресторан_районний", година=19, темп_c=12)
def пул(d):
    r = json.loads(B.виклик("запити", json.dumps(d, ensure_ascii=False)))
    за_ід = {c.get("id"): c for c in B.каталог_останнього_пакета()}     # `метал` речі — те, що читає й композитор
    ю = {с: v for с, v in r["кандидати"].items() if с in Ф._МЕТАЛ_СЛОТИ}
    л = collections.Counter((за_ід.get(x["id"]) or {}).get("метал") or "без слова" for с, v in ю.items() for x in v)
    return sum(map(len, ю.values())), dict(л), sorted(ю), r.get("слоти_випали")
for слова, від_моделі in (("побачення, з золотом", "золото"), ("побачення, без прикрас", "без прикрас"),
                          ("побачення в ресторані", "невідомо")):
    п = PL.паспорт_з_json(json.dumps(dict(подія=слова, нагода="побачення", прикраси=від_моделі), ensure_ascii=False), сц, слова)
    до = {k: v for k, v in п.items() if k != "прикраси"}
    print("«%s» → паспорт.прикраси=%s · рядок: «%s»" % (слова, п["прикраси"], PL.паспорт_рядком(п)[-40:]))
    for мітка, пасп in (("ДО", до), ("ПІСЛЯ", п)):
        n, л, слоти, випали = пул(dict(вх, сценарій=dict(сц), паспорт=пасп))
        print("  %-5s ювелірних у пулі %3d · за металом %s · слотів %d · слоти_випали=%s" % (мітка, n, л, len(слоти), випали))
# суд: бажання переважає драпіровку профілю — суперечність каже hint-регістром, не забороняє
F = B._збірка(вх)[0]
E = [dict(річ="сережки-1", слот="сережки", метал="золото", near=0.9, площа=0.01, lab=(75.0, 5.0, 30.0))]
for драп, баж in ((dict(метал="срібло"), "золото"), (dict(метал="срібло"), None), (dict(метал="золото"), "срібло"), (None, "без прикрас")):
    зн = СБ.метали(E, F, драп=драп, прикраси=баж)
    print("суд: образ веде золото · драп %s · бажання %s → %s" % (драп, баж,
          [(z["правило"], z["сила"], z.get("регістр"), z["сила_нп"], z["суть"][:58]) for z in зн] or "мовчить"))
