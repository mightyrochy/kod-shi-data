"""Рядки 1447, 1604: СКІЛЬКИ «того, чого код не знає» ЙДЕ ДО МОВНОЇ МОДЕЛІ І НА КАРТКУ. Той самий
шлях, що в показі: `запити` → `від_моделі` → `в.питання`; 4 сценарії стенда × 3 форми образу. Лічить
на образ: питань у звіт; з них — для картки (без `для_всіх`: заяви без значень, однакові на кожній картці) і
скільки викликів шару (пачки по 15, як `питаннямиП`); частку питань, однакових на ВСІХ образах.
Запуск із `джерела`: python3 проби/код_не_знає_лічба.py"""
import sys, os, json, collections
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import feed; feed.каталог_на_диску("каталог_повний.xml")
import bridge as B, стенд_знімок as СЗ
СЦ = list(СЗ.СЦЕНАРІЇ.items())[:4]
ФОРМИ = [("верх", "низ", "верхній_шар", "взуття", "сумка", "шарф", "головний_убір"),
         ("сукня", "взуття", "сумка", "пояс", "сережки", "браслет"), ("верх", "низ", "взуття", "сумка")]
вх0, образи = json.load(open("стенд_вх.json")), []
for назва, сц in СЦ:
    вх = dict(вх0, сценарій=сц, випадок=назва)
    к = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False))).get("кандидати") or {}
    for ф in ФОРМИ:
        ід = [к[с][0]["id"] for с in ф if к.get(с)]
        образи.append(json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False))).get("питання") or [])
ключ = lambda п: json.dumps(п.get("повідомлення"), sort_keys=True, ensure_ascii=False)
скрізь = {к for к, n in collections.Counter(к for о in образи for к in {ключ(п) for п in о}).items() if n == len(образи)}
усіх = sum(len(о) for о in образи)
картці = [[п for п in о if п.get("повідомлення") and not п.get("для_всіх")] for о in образи]
print("образів %d · питань у звіт %d (на образ %.1f) · однакових на всіх образах %d (%.0f%%)"
      % (len(образи), усіх, усіх / len(образи), sum(ключ(п) in скрізь for о in образи for п in о),
         100.0 * sum(ключ(п) in скрізь for о in образи for п in о) / max(1, усіх)))
print("для картки (шар пише речення) %d (на образ %.1f) · з них однакових на всіх образах %d · викликів шару на образ %.2f"
      % (sum(map(len, картці)), sum(map(len, картці)) / len(образи), sum(ключ(п) in скрізь for о in картці for п in о),
         sum(-(-len({ключ(п) for п in о}) // 15) for о in картці) / len(образи)))
print("лише у звіт (для_всіх): %d · з них однакових на всіх образах %d"
      % (sum(1 for о in образи for п in о if п.get("для_всіх")), sum(ключ(п) in скрізь for о in образи for п in о if п.get("для_всіх"))))
