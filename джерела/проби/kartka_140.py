# -*- coding: utf-8 -*-
"""Рядок 140 (ручний огляд куратора 23.09.2026), два факти на повному каталозі.
(а) Руки 3–4 — модель без коду й каталогу, речі вигадані: під кожною стояв червоний рядок
«Знімка нема: крамниця не дала у фід жодного знімка цієї речі». Крамниці й фіду в такої речі
нема за побудовою, тобто рядок казав неправду. ДО: `міст_опис.показ` віддавав `чому_без_фото`
на БУДЬ-ЯКИЙ невідомий id. ПІСЛЯ: причина ставиться лише речі, яку каталог знає.
(б) K-ACC-12/07 різали назву посеред слова (`[:44]`, `[:40]`). ПІСЛЯ — `назва_коротко`, по межі
слова з «…». Запуск із теки `джерела`: `python3 проби/kartka_140.py`."""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import міст_опис as МО, аксесуари_структура as АС, feed as Ф
КАТ = "каталог_повний.xml" if os.path.exists("каталог_повний.xml") else "каталог_brief.xml"
оф = Ф.читати_yml(КАТ)[0]
без_фото = next(o["id"] for o in оф if not (o.get("фото") or []))
картки = json.loads(МО.показ(dict(каталог=КАТ, речі=["м-001", "м-002", без_фото])))
вигадані = [к for к in картки if str(к["id"]).startswith("м-")]
справжня = [к for к in картки if к["id"] == без_фото][0]
print("(а) картка показу на трьох речах, каталог %s (%d речей):" % (КАТ, len(оф)))
for к in картки:
    print("   %-38s фото=%-5s чому_без_фото=%s"
          % (str(к["id"])[:38], bool(к.get("фото")), к.get("чому_без_фото") or "—"))
assert all("чому_без_фото" not in к for к in вигадані), "вигаданій речі приписано крамницю"
assert справжня.get("чому_без_фото"), "справжня річ без знімка лишилась без причини"
print("   вигаданих речей із рядком про крамницю: ДО 2 з 2 · ПІСЛЯ 0 з 2;"
      " у справжньої речі без знімка рядок лишився")

довгі = sorted({o.get("назва") or "" for o in оф
                if Ф.слот(o) in ("сумка", "шарф") and len(o.get("назва") or "") > 44})
посеред = [н for н in довгі if н[43:45].strip() and not н[43].isspace() and not н[44].isspace()]
print("\n(б) назв сумок і шарфів понад 44 символи: %d; з них голий зріз [:44] рубав посеред слова: %d"
      % (len(довгі), len(посеред)))
for н in посеред[:3]:
    print("   ДО    «%s»\n   ПІСЛЯ «%s»" % (н[:44], АС.назва_коротко(н, 44)))
assert all(АС.назва_коротко(н, 44).endswith("…") and len(АС.назва_коротко(н, 44)) <= 44 for н in довгі)
assert not [н for н in довгі if АС.назва_коротко(н, 44)[:-1].rstrip() != АС.назва_коротко(н, 44)[:-1]]
print("   усі %d обрізаються по межі слова, з «…», і жодна не довша за стелю 44" % len(довгі))
print("kartka_140: зелено")
