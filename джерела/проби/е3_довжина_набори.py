"""Повний каталог і граничні входи `верхнє_довжина` для звірки ваги (Е3-сила-правила)."""
import gzip, json, os, pathlib


def набори():
    """(назва, функція, речі, тіло): кожна річ каталогу й кожна сигнатура краю, без моделі."""
    import areas, feed as Ф, верхнє_довжина as Д
    тіла = {h: dict(зріст=float(h), висоти=areas.висоти_рівнів(h)) for h in (150, 155, 160, 165, 170, 175, 180)}
    кеш = pathlib.Path(os.environ.get('TMP') or '/tmp') / 'е3_каталог.json.gz'
    if not кеш.exists():
        к = Ф.база_прогону(Ф.каталог_на_диску('каталог_повний.xml'), ліміт_фото=0)['каталог']
        json.dump(к, gzip.open(кеш, 'wt', encoding='utf-8'), ensure_ascii=False)
    к = json.load(gzip.open(кеш, 'rt', encoding='utf-8'))
    for в in json.loads((pathlib.Path(__file__).parent / 'дані/е3_довжина_межі.json').read_text(encoding='utf-8')):
        yield 'межа:' + в['назва'], в['функція'], в['речі'], тіла[в['зріст']]
    підпис = lambda р: repr((Д.довжина_виробу(р), р.get('довжина_рівень'), р.get('низ_см'),
                             р.get('край_джерело'), р.get('ховає_повністю'), р.get('стан')))
    за = {сл: [р for р in к if р.get('слот') == сл] for сл in ('верхній_шар', 'сукня', 'низ', 'верх')}
    реп = {сл: list({підпис(р): р for р in рр}.values()) for сл, рр in за.items()}
    низи = реп['сукня'] + реп['низ']
    for в in за['верхній_шар']:
        for h, т in тіла.items():
            yield 'довжина:%s@%s' % (в['id'], h), 'довжина', [в], т
        for н in низи[::max(1, len(низи) // 3)]:
            yield 'край:%s|%s' % (в['id'], н['id']), 'краї', [в, н], тіла[165]
    for н in за['сукня'] + за['низ']:
        for в in реп['верхній_шар'][::max(1, len(реп['верхній_шар']) // 2)]:
            yield 'край:%s|%s' % (в['id'], н['id']), 'краї', [в, н], тіла[165]
    for в in реп['верхній_шар']:
        for н in низи:
            yield 'підпис:%s|%s' % (в['id'], н['id']), 'краї', [в, н], тіла[165]
    міряні = lambda сл: [р for р in реп[сл] if Д.довжина_виробу(р)[1] == 'лінія_плеча']
    for в in міряні('верхній_шар'):
        for с in міряні('верх'):
            for н in міряні('сукня'):
                дв, дс, дн = (Д.довжина_виробу(х)[0] for х in (в, с, н))
                if all(0.0 <= а - б <= 7.5 for а, б in ((дв, дс), (дс, дн))) or all(0.0 <= а - б <= 7.5 for а, б in ((дв, дн), (дн, дс))):
                    yield 'каскад:%s|%s|%s' % (в['id'], с['id'], н['id']), 'краї', [в, с, н], тіла[165]
