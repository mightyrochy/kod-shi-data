"""Той самий каталог і оцінки стилістки: образ, адреси й турнір на 30 перестановках."""
import json, pathlib, random, sys
sys.path.insert(0, sys.argv[1] if len(sys.argv) > 1 else str(pathlib.Path(__file__).resolve().parents[1]))
import feed, пакет_моделі as П, уважний_вибір as У


def головна():
    """Переставляє слоти та речі, зберігаючи оцінки, сід і сам каталог."""
    речі = feed.база_прогону(str(pathlib.Path(__file__).resolve().parents[1] / 'каталог_brief.xml'),
                           ліміт_фото=0)['каталог']
    база = {с: [r for r in речі if r.get('слот') == с] for с in ('верх', 'низ', 'взуття', 'сумка')}
    образи, адреси, турніри = [], [], []
    for н in range(30):
        р = random.Random(н); слоти = list(база); р.shuffle(слоти)
        кандидати = {}
        for с in слоти:
            кандидати[с] = list(база[с]); р.shuffle(кандидати[с])
        ном, _ = П.номери_речей(кандидати)
        ід = {'#%d·%s' % v: к for к, v in ном.items()}
        пул = {с: [dict(н='#%d·%s' % ном[r['id']]) for r in рч] for с, рч in кандидати.items()}
        пак = dict(кандидати=кандидати, пакет=dict(пул=пул, завдання=dict(образів=3),
                   обмеження={"обов'язкові_слоти": ['взуття', 'сумка']}))
        for сід in (0, 4242):
            о, _ = У.скласти_за_оцінками(пак, {к: У.ПАСУЄ for к in ід}, сід=сід)
            образи.append((сід, [sorted(ід[к] for к in x['речі']) for x in о['образи']]))
        адреси.append(ном)
        турніри.append(У.групи_турніру(пул, 4242))
    факти = dict(перестановок=30, речей=sum(map(len, база.values())),
                 образ=sum(v != образи[i % 2] for i, v in enumerate(образи)),
                 адреси=sum(v != адреси[0] for v in адреси),
                 турнір=sum(v != турніри[0] for v in турніри))
    print(json.dumps(факти, ensure_ascii=False))
    return int(any(факти[к] for к in ('образ', 'адреси', 'турнір')))


if __name__ == '__main__':
    sys.exit(головна())
