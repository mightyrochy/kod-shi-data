"""КОЛО-2, рядок 1610: скільки місць рахують ВІДНОШЕННЯ схем кутом CIELAB, а не колом художника.
Дві міри: (1) текстом — вирази «(h ± зсув) % 360» у модулях схем і палітри; (2) поведінкою — для
кожної схеми (`палітра_схеми.СХЕМИ`) і відношення (`cs.RELATIONS`, `cs.центри_відношення`) на якорях
0…355° крок 5°: центр дуги ролі мусить стояти від якоря на номінальний зсув НА КОЛІ (±1°).
Запуск із `джерела`: python3 проби/коло2_місця.py (каталог не потрібен)."""
import sys, pathlib, re
К = pathlib.Path(__file__).resolve().parent.parent; sys.path.insert(0, str(К))
import colorspace as cs, палітра_схеми as PS
ФАЙЛИ = ("колір_простір_риси.py", "палітра_схеми.py", "palettes.py", "personal_palette.py",
         "палітра_специфікація.py", "палітра_запити.py", "суд_від_моделі.py", "вибір_палітри.py")
ВИРАЗ = re.compile(r"\(\s*(?:float\()?h\)?\s*[+-]\s*(?:\d+|off)\s*\)\s*%\s*360")
текст = {f: len(ВИРАЗ.findall((К / f).read_text(encoding="utf-8"))) for f in ФАЙЛИ}
кут = lambda a, b: abs((a - b + 180) % 360 - 180)
на_колі = lambda h, c: (cs.у_коло_художника(c) - cs.у_коло_художника(h)) % 360
НОМІНАЛ = {"аналогова": dict(домінанта=0, секундант=30, акцент=55),
           "тріада": dict(домінанта=0, секундант=120, акцент=240),
           "приглушена_комплементарна": dict(домінанта=0, секундант=180, акцент=180)}
хибні = set()
for h in range(0, 360, 5):
    for схема, ролі in НОМІНАЛ.items():
        for роль, дуга in PS.СХЕМИ[схема]["тон"](float(h)).items():
            ц = (дуга[0] + ((дуга[1] - дуга[0]) % 360) / 2) % 360
            if кут(на_колі(h, ц), ролі[роль]) > 1: хибні.add("%s.%s" % (схема, роль))
    for rel, (off, _w) in cs.RELATIONS.items():
        for ц, ном in zip(cs.центри_відношення(float(h), rel), (off, -off)):
            if кут(на_колі(h, ц), ном % 360) > 1: хибні.add("RELATIONS.%s%+d" % (rel, ном))
print("текстом (h±зсув)%%360: %d · %s" % (sum(текст.values()), {f: n for f, n in текст.items() if n}))
print("поведінкою (центр не на номінальному кроці кола): %d · %s" % (len(хибні), sorted(хибні)))
print("ФАКТ · відношення схем кутом CIELAB: текстом %d, поведінкою %d" % (sum(текст.values()), len(хибні)))
