# -*- coding: utf-8 -*-
"""Друкує виходи локальних правил без добору: вимір лишається, заміни немає."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import accessory as А
import дріт_моделі as Д

def перевірити():
    """Звіряє текст і дріт на вимірах різних аксесуарів та обох боках розміру."""
    зн = []
    for слот, поле, вимір in [('взуття', 24, 250), ('взуття', 29, 250),
                             ('окуляри', '40-10-140', 70), ('головний_убір', 50, 56),
                             ('годинник', 60, 15)]:
        сп = А.АКСЕСУАР_ВИМІР[слот]
        зн.append(А._ворота_однієї(слот, сп, {'id': слот, сп['поле']: поле},
                                 слот, {сп['вимір']: вимір})[1])
    пара = dict(id='пара', слот='взуття', тип='балетки', повнота='вузька',
                розмірність='маломірить', каблук_см=8, ремонтопридатна=False, ціна_ранг=0.9)
    зн += А.ширина_й_розмір([пара]) + А.цінність_речей([пара])
    зн += А.маса_взуття([пара, dict(id='низ', слот='низ', тканина='твід')])
    зн += А.вартість_носіння([пара], 8, 'бруківка')
    for пах in (70, 95):
        for нюд in (False, True):
            зн += А.подовження_ноги(dict(зріст=170, висоти={'пах': пах}, виміряні_рівні=['пах']),
                                    [dict(пара, нюд=нюд)])
    зн += А.кольє_проти_горловини(dict(висоти={'плечі': 130}),
        [dict(id='кольє', слот='прикраси', ланцюг_см=32), dict(id='верх', слот='верх', виріз_тип='V-подібний')])
    assert len(зн) == 16 and all(з and з.get('заяви') for з in зн)
    for з in зн:
        assert isinstance(з.get('ремонт'), str) and з['ремонт']
        assert not з.get('ремонт_заяви') and 'fix' not in Д._знахідка(з)
    питання = А._ворота_однієї('взуття', А.АКСЕСУАР_ВИМІР['взуття'], {'id': 'пара'}, 'пара', {})[1]
    assert питання['контракт'] and питання['ремонт'] != зн[0]['ремонт']
    print('Знахідки: 16; пояснення спільного джерела: 16; заміни на дроті: 0; запит виміру збережено')


if __name__ == '__main__':
    перевірити()
