"""Н-2: «третя річ» і «мінімум речей» — гейт, крім спеки й сукні з власним фокусом.

Рішення власника «13А» (28.09.2026). Звіт Research про композицію міряє доказ під
цими рядками: третя річ — клас C (практика), саме число — клас D (традиція). У спеку
й на statement-сукні правило ламається, і образ має їхати на картку з приміткою, а не
в ремонт. Проба судить ОДИН І ТОЙ САМИЙ образ (сукня + взуття + сумка, речей 3 при
мінімумі 4) у трьох умовах і дивиться, що вийшло блокером, а що — реплікою.
Запуск із теки `джерела`: `python3 проби/н2_третя_річ_слабко.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import суд_від_моделі as СМ

тиха = dict(id="сукня", слот="сукня", hex="#8a8a8a")          # нейтраль, без принта
гучна = dict(id="сукня", слот="сукня", hex="#8a8a8a", візерунок="квітковий")
решта = [dict(id="човники", слот="взуття", hex="#1c1c22"),
         dict(id="клатч", слот="сумка", hex="#2e2e38")]
випадки = [("прохолодно, тиха сукня", тиха, dict(темп_c=12.0)),
           ("СПЕКА +28 °C, тиха сукня", тиха, dict(темп_c=28.0)),
           ("прохолодно, сукня з принтом", гучна, dict(темп_c=12.0))]
for ім, сукня, сц in випадки:
    речі = [dict(сукня)] + [dict(r) for r in решта]
    бл, мʼякі = СМ.структура_образу_заяви(речі, None, сц)
    коди = lambda xs: sorted({з.get("code") for з in xs})
    з_бл = [з for _, зз in бл for з in зз]
    print("ФАКТ · %-28s блокерів %d %s · реплік %d %s"
          % (ім, len(бл), коди(з_бл), len(мʼякі), коди([з for z in мʼякі for з in z["заяви"]])))
    for z in мʼякі:
        assert z["регістр"] == "репліка" and z.get("гейт_знято_бо"), z
    if ім.startswith("прохолодно, тиха"):
        assert {"needs_third_piece", "too_few_items"} <= set(коди(з_бл)) and not мʼякі
    else:
        assert not [з for з in коди(з_бл) if з in ("needs_third_piece", "too_few_items")], бл
        assert {"needs_third_piece", "too_few_items"} == set(
            коди([з for z in мʼякі for з in z["заяви"]])), мʼякі
print("ФАКТ · поле, яким названо зняття гейта: «гейт_знято_бо» — %s" % мʼякі[0]["гейт_знято_бо"][:60])
