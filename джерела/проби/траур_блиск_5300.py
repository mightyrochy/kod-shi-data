"""Друкує коди блиску взуття й сумок, які лишає чинний траурний відсів."""
import collections
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import feed
import траурний_регістр as Т


def головна():
    """Звірити похорон, відсутність трауру й матові речі на одному каталозі."""
    шлях = feed.каталог_на_диску(sys.argv[1] if len(sys.argv) > 1 else None)
    каталог = feed._прочитати_каталог(шлях, 0)["каталог"]
    траур = Т.траур_випадку("траур", "похорон")
    речі = [р for р in каталог if р.get("слот") in ("взуття", "сумка")]
    блискучі = [р for р in речі if Т._блиск_кодом(р.get("блиск")) in (2, 3)]
    лишились = [р for р in блискучі if not Т.траурне_відсічення(р, траур)]
    print("каталог", len(каталог), "взуття_сумки", len(речі))
    print("блиск_2_3", len(блискучі), "лишились", len(лишились))
    print("лишились_слоти", dict(collections.Counter(р["слот"] for р in лишились)))
    print("лишились_блиск", dict(collections.Counter(р["блиск"] for р in лишились)))
    print("без_трауру_відсічено", sum(bool(Т.траурне_відсічення(р, None)) for р in каталог))
    матові = [р for р in речі if Т._блиск_кодом(р.get("блиск")) == 0]
    print("матові", len(матові), "лишились", sum(not Т.траурне_відсічення(р, траур) for р in матові))
    поля = ("id", "слот", "блиск", "блиск_джерело", "блиск_крамниці")
    for р in каталог:
        if р["id"] == "ж-09241@cultboutique.com.ua":
            факт = {к: р.get(к) for к in поля}
            факт.update(оздоба=Т.святкова_оздоба(р), відсічення=Т.траурне_відсічення(р, траур))
            print(json.dumps(факт, ensure_ascii=False, sort_keys=True))


if __name__ == "__main__":
    головна()
