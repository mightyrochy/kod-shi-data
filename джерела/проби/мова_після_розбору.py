# -*- coding: utf-8 -*-
"""Вихідний перекладач працює ЛИШЕ з кінцевим текстом для людини, ПІСЛЯ розбору коду (знахідка
ноутбука, Lapa, PR #304 П.6: «Твоя річ:» стало «Твої речі:» у 3 текстах). Друкує: що код
знаходить у сирому тексті руки без каталогу і що знайшов би в перекладеному; і де в показі
стоїть розбір (`відМоделіРуки` → міст `від_моделі`) відносно викликів шару.
Запуск: cd джерела && python3 проби/мова_після_розбору.py"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import розбір_відповідей as Р, річ_з_фото as РФ, мовний_шар as М
СИРИЙ = ("Образ:\n- Твоя річ: спідниця міді червона #b22234\n- блуза біла #f5f5f0\n"
         "- човники чорні #1a1a1a\n- сумка чорна #111111")
ЇЇ = [{"фото": "ф1", "назва": "спідниця з фото", "слот": "низ", "колір": "червоний", "закріплена": True}]
розмітка = М.розмітити({"опис": СИРИЙ})                  # перекладач міняє мітку, як Lapa
відповідь = json.dumps({"1": СИРИЙ.replace("Твоя річ:", "Твої речі:")}, ensure_ascii=False)
ПЕРЕКЛАДЕНИЙ = М.прийняти(розмітка, відповідь)["тексти"]["опис"]
for де, т in (("сирий текст моделі (його читає код)", СИРИЙ), ("текст після перекладача", ПЕРЕКЛАДЕНИЙ)):
    _, стан = РФ.впізнати_в_тексті(Р.перевірити_образ_моделі(т, None).get("речі"), ЇЇ)
    print("%-38s → її річ названо %d із %d%s" % (де, стан["названо"], стан["закріплено"],
          "" if not стан["чому"] else " · " + стан["чому"]))
п = open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "показ.html"),
         encoding="utf-8").read().split("\n")
рядок = lambda шаблон: next(і + 1 for і, р in enumerate(п) if re.search(шаблон, р))
розбір, гейт, картка = рядок(r"await відМоделіРуки\("), рядок(r"await мовоюП\(тш"), рядок(r"await мовоюКарткуП\(картка")
print("показ.html: розбір сирого тексту (перший `відМоделіРуки`) — рядок %d; шар на мовному гейті — %d; "
      "шар картки — %d" % (розбір, гейт, картка))
print("розбір раніше за шар:", розбір < гейт < картка,
      "· вихід шару на гейті знову в розбір не йде:",
      not any("відМоделіРуки" in р and "стало" in р for р in п[гейт:гейт + 20]))
