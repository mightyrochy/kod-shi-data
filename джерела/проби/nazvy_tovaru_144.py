# -*- coding: utf-8 -*-
"""Рядок 144: назва на картці — людська назва речі мовою картки.
ДО — `<name>` фіду як є (так його показувала картка до цієї гілки), ПІСЛЯ — `назва_речі.назва_для_показу`.
Запуск: cd джерела && python3 проби/nazvy_tovaru_144.py"""
import collections, os, re, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import feed, назва_речі as НР
оф = feed.читати_yml(feed.каталог_на_диску())[0]
карта = НР.читати_назви_карток()
КЛАСИ = (("HTML-сутність", r"&[a-zA-Z]+;|&#\d+;"), ("рекламний хвіст", r"артикул|\bціна\b|[✅⭐⚡❤🤍👍⬆]|в інтернет[-\s]?магазин"),
         ("службовий код/розмір", r"\b\d{5,}\b|\(\s*\d{1,3}\s*,[^)]*\)|\b\d{3,5}-\d{1,4}\b|,\s*\d{2}\s*$"),
         ("чужий блок сторінки", r"дивіть?ся також|смотрите также"),
         ("HTML-теґ", r"<[a-z/!]"))
до, після, змін = collections.Counter(), collections.Counter(), 0
джерела, причини, по_маг, всього = (collections.Counter(), collections.Counter(),
                                    collections.Counter(), collections.Counter())
for o in оф:
    р = НР.назва_для_показу(o, карта)
    джерела[р["джерело"]] += 1; всього[o["магазин"]] += 1
    причини[str(р["причина"] or "—").split(" (")[0]] += 1
    if р["назва"] != o["назва"]:
        змін += 1; по_маг[o["магазин"]] += 1
    for імя, рх in КЛАСИ:
        до[імя] += bool(re.search(рх, o["назва"], re.I)); після[імя] += bool(re.search(рх, р["назва"], re.I))
    до["ВЕЛИКІ ЛІТЕРИ"] += НР._велики_літери(o["назва"]); після["ВЕЛИКІ ЛІТЕРИ"] += НР._велики_літери(р["назва"])
    if НР.чужа_мова(o["назва"]): до["чужа мова"] += 1
    if НР.чужа_мова(р["назва"]): після["чужа мова"] += 1
print("ФАКТ · оферів %d · назва змінилась %d (%.1f %%) · крамниць зачеплено %d із %d"
      % (len(оф), змін, 100.0 * змін / len(оф), len(по_маг), len(всього)))
print("ФАКТ · джерело назви: %s" % dict(джерела))
print("ФАКТ · причина заміни: %s" % {k: v for k, v in причини.items() if k != "—"})
for імя in [k for k, _ in КЛАСИ] + ["ВЕЛИКІ ЛІТЕРИ", "чужа мова"]:
    print("ФАКТ · %-22s ДО %5d → ПІСЛЯ %5d" % (імя, до[імя], після[імя]))
print("ФАКТ · топ-10 крамниць (змінено / усього): %s"
      % ", ".join("%s %d/%d" % (м, n, всього[м]) for м, n in по_маг.most_common(10)))
чужі = [o for o in оф if re.search(r"дивіть?ся також", o["назва"], re.I)]
print("ФАКТ · записів із чужого блоку сторінки: %d · виправлено на справжній товар: %s"
      % (len(чужі), [(o["id"].split("@")[0], НР.назва_для_показу(o, карта)["назва"]) for o in чужі]))
