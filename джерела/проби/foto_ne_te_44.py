# -*- coding: utf-8 -*-
"""Рядок 44 БЕКЛОГУ: живий шлях ДВОМА викликами моста, без моделі. `foto_ne_te.py`
(#106) довела резолв «#N·код»→річ у межах ОДНОГО виклику; лишалась гіпотеза, що
номери розходяться МІЖ викликами — роздає їх пул кроку вибору, а розбирає пул,
який `від_моделі` будує вдруге на кроці опису. Тут іде ланцюг показу: `запити` →
ОБРАЗИ_V1 → ВИБІР_V1 → `опис` → ОПИС_ВІДПОВІДЬ_V1 з номером РІВНО однієї речі в
«фото_не_те». Друга колонка — вхід правила: скільки позначок код знімає доказом
`фото_слот` («річ на фото доведено є»). `python3 проби/foto_ne_te_44.py`."""
import sys, os, json, tempfile, itertools
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(sys.path[0])
import bridge as B, feed as Ф, pipeline as PL
кл = lambda d: json.loads(B.виклик("від_моделі", json.dumps(d, ensure_ascii=False)))


def прогін(кат, сід):
    вх = json.load(open("стенд_вх.json", encoding="utf-8"))
    вх.update(каталог=Ф.каталог_на_диску(кат), сід=сід, намір="conventional",
              кеш_кольорів=os.path.join(tempfile.gettempdir(), "кеш_44.json"))
    з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    к = з["кандидати"]; ном = PL.номери_речей(к)[0]; вб = {"ід": []}
    # Четверту річ ядра доводиться ШУКАТИ: `вибір_з_json` не приймає образ із незакритим
    # гейтом (на повному каталозі перша прикраса падає на K-PAL-03), а проба міряє резолв.
    for дод, i in itertools.product(("прикраси", "пояс", "шарф"), range(3)):
        ядро = [(к.get(с) or [{}])[0].get("id") for с in ("сукня", "взуття", "сумка")]
        ядро += [(к.get(дод) or [])[i]["id"] if len(к.get(дод) or []) > i else None]
        if not all(ядро): continue
        вн = кл(dict(вх, текст_моделі=json.dumps(dict(версія="1", образи=[dict(ід="о1", підпис="проба 44",
            речі=["#%d·%s" % ном[x] for x in ядро])]), ensure_ascii=False)))["вибір_над"]
        вб = кл(dict(вх, ітерація=2, відповідь="ВИБІР_V1", вибір_над=вн, текст_моделі=json.dumps(
            dict(версія="1", обрано=вн["образи"][0]["ід"]), ensure_ascii=False)))["вибір"]
        if вб["ід"]: break
    assert вб["ід"], "жодне ядро не пройшло гейти: %s" % (вб.get("чому_відмова") or "")[:120]
    оп = json.loads(B.виклик("опис", json.dumps(dict(вх, речі=вб["ід"], номери=вб["номери"],
                                                     образ=вб["обрано"]), ensure_ascii=False)))
    розб, знято = [], 0
    for ціль in вб["ід"]:
        о4 = кл(dict(вх, ітерація=2, відповідь="ОПИС_ВІДПОВІДЬ_V1", ід=вб["ід"], текст_моделі=json.dumps(
            dict(версія="1", текст="Проза для жінки, звичайне речення.", як_носити=[],
                 фото_не_те=[вб["номери"][ціль]]), ensure_ascii=False)))["опис"]
        зн = [x["id"] for x in (о4.get("фото_не_ті_знято") or [])]; знято += len(зн)
        if о4["фото_не_ті"] + зн != [ціль]:
            розб.append("    РОЗБІЖНІСТЬ: %s → %s, чекали %s" % (вб["номери"][ціль], о4["фото_не_ті"] + зн, ціль))
    print("%-19s сід %-6d пул %4d · номери опису = номери вибору: %s · розбіжностей %d · знято доказом %d/%d"
          % (кат, сід, з["пул_речей"], {р["н"] for р in оп["опис"]["образ"]["речі"]}
             == set(вб["номери"].values()), len(розб), знято, len(вб["ід"])), *розб, sep="\n")
    return len(розб)


збої = sum(прогін(к, с) for к in ("каталог_brief.xml", "каталог_повний.xml") for с in (4242, 7, 12345))
print("ВИСНОВОК: розбіжностей номер→річ на живому шляху — %d" % збої)
sys.exit(1 if збої else 0)
