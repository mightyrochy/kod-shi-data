"""«Останній ярус перед очима жінки» стоїть не на всіх текстах картки.

`безМашинногоСліду` чистить опис, «Як це носити» і «код не знає», але НАЗВУ речі
(і рядки під нею) картка малює сирою — а назви рук 3–4 модель пише реченнями з
hex усередині. Друкує, які тексти картки через чистку йдуть, а які ні, і скільки
машинних слідів лишилось у назвах речей власника.
"""
import json
import pathlib
import re

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
ПОКАЗ = (КОРІНЬ / "джерела" / "показ.html").read_text(encoding="utf-8")
рядки = ПОКАЗ.splitlines()
поч = next(i for i, р in enumerate(рядки) if "function рендерКартку" in р)
кін = next(i for i, р in enumerate(рядки) if "function підвʼязатиКартку" in р)

ЧИСТКА = "безМашинногоСліду"
print("рендерКартку: рядки %d…%d · викликів чистки в ньому: %d"
      % (поч + 1, кін, sum(ЧИСТКА in рядки[i] for i in range(поч, кін))))
for i in range(поч, кін):
    р = рядки[i].strip()
    if re.search(r"(назваЧ|'тьм'|чому_без_фото|пом_якшення|чому_додав|неповний|схема_жінці)", р) and ("appendChild" in р or "textContent" in р):
        print("   %s показ.html:%d %s" % ("чисто " if ЧИСТКА in р else "СИРЕ  ", i + 1, р[:110]))

HEX = re.compile(r"#[0-9a-fA-F]{6}\b")
ІД = re.compile(r"(?<![\w])м-\d{3,}(?![\w])")
сліди = {}
for ф in sorted((КОРІНЬ / "аудит" / "тести" / "власник_2026-09-25").glob("verdykty-*.json")):
    д = json.loads(ф.read_text(encoding="utf-8"))
    for п in д["прогони"]:
        for в in п["вердикти"]:
            for р in в.get("речі_образу") or []:
                н = str(р.get("назва") or "")
                if HEX.search(н) or ІД.search(н):
                    сліди[н] = (п["спільне"].get("розклад"), в.get("рука"))
for н, (розклад, рука) in сліди.items():
    print("   розклад %s · рука %s · назва на картці: «%s»" % (розклад, рука, н))
print("назв із машинним слідом у файлах власника:", len(сліди))
