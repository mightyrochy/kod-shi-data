# -*- coding: utf-8 -*-
"""М-5 п.5: однакова розмова → однаковий паспорт. Код: промпт ходу — байт у байт той самий на кожен повтор тієї
самої розмови, вибірка — температура 0 (М-2), шов із тією самою відповіддю моделі дає той самий паспорт. З MODEL —
ще й жива модель двічі на той самий промпт кожного ходу (`м5_розмови.json`, «після»): чи збігся розібраний хід.
Запуск: cd джерела && [MODEL=… MODEL_URL=…] python3 проби/м5_стабільність.py"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import мова_спільне as С
М, дамп = С.М, lambda x: json.dumps(x, ensure_ascii=False, sort_keys=True)
промптів = паспортів = живих = 0
розійшлись = []
for р in json.load(open(os.path.join(С.ТУТ, "м5_розмови.json"), encoding="utf-8")):
    п, історія, її = {}, [], []
    for х in р["ходи"]:
        її.append(х["вона"])
        вхід = {"розмова": {"нове": х["вона"], "історія": історія}, "сценарій": {}, "паспорт": п}
        а, б = (json.loads(М.мова(json.loads(json.dumps(вхід)))) for _ in range(2))
        промптів += 1
        if а["промпт"] != б["промпт"] or а["вибірка"] != {"temperature": 0}:
            розійшлись.append("%s · хід %d: промпт чи вибірка" % (р["назва"], len(її)))
        дельта = М.прийняти_вхід("scenario", json.dumps(х.get("після", х.get("обидва"))))["внутрішня"]
        шв = [json.loads(М.мова({"паспорт_з": дельта, "сценарій": {}, "паспорт": п, "слова_розмови": її,
                                 "частини": {"need": "none", "text": "Записала."}})) for _ in range(2)]
        паспортів += 1
        if дамп(шв[0]["паспорт"]) != дамп(шв[1]["паспорт"]) or шв[0]["текст"] != шв[1]["текст"]:
            розійшлись.append("%s · хід %d: паспорт шва" % (р["назва"], len(її)))
        if С.МОДЕЛЬ:
            живі = [М.прийняти_розмову(С.модель(а["промпт"])[0]) for _ in range(2)]
            живих += 1
            if дамп(живі[0]["внутрішня"]) != дамп(живі[1]["внутрішня"]):
                розійшлись.append("%s · хід %d: жива модель двічі — різні ходи" % (р["назва"], len(її)))
        п = шв[0]["паспорт"]
        історія += [{"хто": "людина", "текст": х["вона"]}, {"хто": "ші", "текст": шв[0]["текст"] or "Записала."}]
print("промптів двічі: %d · паспортів шва двічі: %d · живих пар: %d%s" % (промптів, паспортів, живих, (" (" + С.МОДЕЛЬ + ")") if С.МОДЕЛЬ else ""))
print("розійшлось: %d%s" % (len(розійшлись), "".join("\n  ✗ " + x for x in розійшлись)))
sys.exit(1 if any("жива" not in x for x in розійшлись) else 0)
