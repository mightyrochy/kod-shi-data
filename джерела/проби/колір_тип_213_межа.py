"""Спільний читач відкидає залишкову точку інтервалу в продуктовому описі."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import колір_річ as К
import приміряння as П


def головна():
    """Перевірити тип, значення й походження на одній межі читання."""
    вимір = dict(hex="#112233", lab=(20, 1, 2), колір_тип="вимір")
    інтервал = dict(вимір, колір_тип="інтервал", колір_не_вимір=dict(
        свідок="shop_word", вікно=(10, 50, 0, 30, (240, 310))))
    невідоме = dict(інтервал, колір_тип="невідомо")
    assert К.hex_кольору(вимір) == "#112233"
    assert К.hex_кольору(dict(hex="#112233")) == "#112233"
    assert К.hex_кольору(dict(lab=(20, 1, 2))) is None
    for колір in (інтервал, невідоме):
        assert К.hex_кольору(колір) is None and К.точка_кольору(колір) is None
        assert "color_hex" not in П.опис_речі(колір)
    assert К.межі_кольору(інтервал) == (10, 50, 0, 30, (240, 310))
    assert К.межі_кольору(невідоме) is None
    assert П.опис_речі(вимір)["color_hex"] == "#112233"
    print("Межа читача: вимір збережено; інтервал і невідоме не передають hex моделі")


if __name__ == "__main__":
    головна()
