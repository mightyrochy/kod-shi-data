# -*- coding: utf-8 -*-
"""K-COL-08 (розміщення = керування увагою) — уже покрито K-PAL-09, окрім половини без входу.

Корпус (тема-4:311) ділить механізм надвоє: (a) тепле наближає / холодне віддаляє —
`hint`; (b) темне й матове ЗМЕНШУЄ видимий розмір — T1, несуча половина; і одне
приписне речення: «постав наступальні властивості туди, куди має йти око».
ВЛАСНОГО ЕМІТЕНТА K-COL-08 у коді нема й не потрібно: `palettes.ПРИЙОМИ`
оголошує прийом «розміщення» з ід K-PAL-09 і джерелом «K-COL-08; практики “worst
colours away from the face”; Chevreul R-CHEV-15», і з 17.09 саме він СУДИТЬ образ
у `pipeline.палітра_образу`. Другого емітента тут не заводимо — це був би той
самий механізм удвічі.
ЧОГО НЕ ПОКРИТО, І ЦЕ БЕЗ ВХОДУ: «туди, куди має йти око» потребує ОГОЛОШЕНОЇ
фокусної зони; її не називає ніхто — `status.ОБМЕЖЕННЯ["фокусна_зона"]`, і те
саме вголос каже `суд_образу.фокуси`. Запуск із теки `джерела`:
`python3 проби/col_K-COL-08.py`."""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pal_вердикт as ПВ
import palettes as PAL, pipeline as PL, status as СТ, колір_образу as КО

розм = PAL.ПРИЙОМИ["розміщення"]
print("прийом «розміщення» → ід %s · джерело «%s» · сила %s"
      % (розм["ід"], розм["джерело"][:46], розм["сила"]))
обм = next(x for x in СТ.ОБМЕЖЕННЯ if x["id"] == "фокусна_зона")
print("друга половина без входу: %s · перевірка=%s" % (обм["наслідок"][:64], обм["перевірка"]))
вх, r, кат, спец = ПВ.стенд(гілка=0)
П = спец["палітра_практична"]
поза = lambda L, C, h, _: (not PL._нейтральний_тон(h, C, L)) and not PL._у_вікнах(П["вікна"], L, C, h)
біля = ПВ.взяти(r, кат, "верх", поза) or ПВ.з_каталогу(кат, "верх", поза)   # near 0.90
далі = [ПВ.взяти(r, кат, с, lambda *a: True) for с in ("низ", "взуття", "сумка")]
print("біля обличчя «%s» (вага слота «верх» %.2f ≥ поріг %.2f)"
      % ((біля or {}).get("назва", "—")[:40], КО.SLOT_NEAR_FALLBACK["верх"], КО.NEAR_МІН))
зн, _ = ПВ.знахідки(вх, [x["id"] for x in [біля] + далі if x])
print("ФАКТ · K-PAL-09 (механізм K-COL-08): %s" % ПВ.рядок(зн, "K-PAL-09"))
z = next((x for x in зн if x.get("правило") == "K-PAL-09"), None)
assert z, "колір поза палітрою біля обличчя не дав знахідки"
assert розм["ід"] == "K-PAL-09" and "K-COL-08" in розм["джерело"], розм
assert обм["перевірка"] is None and "K-COL-08" in обм["що"], обм   # вимкнено чесно
print("       ремонт: %s" % z["ремонт"])
