"""Повний каталог і граничні входи принтів (K-COL-10, R-PRN-*, P-PRT-*) для звірки ваги."""
import gzip, itertools, json, os, pathlib

МАСШТАБИ = [(None, None), (0.1, 0.1), (0.1, 0.13), (0.1, 0.16), (0.1, 0.2), (0.1, 0.4)]


def набори():
    """Віддати (назва, функція, args, kwargs) без моделі; той самий вхід для ДО і ПІСЛЯ."""
    import outfit as О, colorspace as cs
    with gzip.open(pathlib.Path(os.environ['TMP']) / 'е3_каталог.json.gz', 'rt', encoding='utf-8') as ф:
        каталог = json.load(ф)
    класи = {}
    for р in каталог:
        if р.get('візерунок') not in (None, 'solid'):
            класи.setdefault(р['візерунок'], []).append(р)
    імена = sorted(класи)
    пари = []
    for к, група in sorted(класи.items()):
        пари += [('однакові', а, б) for а, б in zip(група, група[1:])]
        for і, а in enumerate(група):
            for інший in імена[(імена.index(к) + 1):] + імена[:імена.index(к)]:
                if (і + len(інший)) % 3 == 0:
                    б = класи[інший][і % len(класи[інший])]
                    пари.append(('різні', а, б))
    for і, (вид, а, б) in enumerate(пари):
        for ма, мб in (МАСШТАБИ if вид == 'однакові' or і % 4 == 0 else МАСШТАБИ[:1]):
            речі = [dict(а, масштаб_відн=ма), dict(б, масштаб_відн=мб)]
            yield '%s|%s|%s|%s' % (а['id'], б['id'], ма, мб), 'принти', [речі, О.елементи(речі)], {}
    F = [None] + [cs.features(cs.hx(ш), cs.hx(в), cs.hx('#759087'))
                  for ш, в in (('#deb295', '#f1dbaa'), ('#f3d9c4', '#2b1d14'), ('#8d5a3b', '#1a1210'))]
    сітка = itertools.product([None, 0.02, 0.1, 0.3, 0.6], [None, 0.05, 0.5, 0.95], [None, 0.3, 0.6, 0.9],
                              [None, 10.0, 60.0], [None, 0.0, 0.5, 1.0], range(len(F)),
                              [(None, None), ('верх', 'верх'), ('верх', 'низ')],
                              [(None, None), ('круглий', 'лінійний'), ('круглий', 'круглий'), ('мішаний', 'лінійний')])
    for м, чк, ґр, кп, мо, ф, (зона, слот), (рух, рр) in сітка:
        пал = dict(масштаб_відн=м, чіткість_краю=чк, ґрунт=ґр, контраст=кп, гучність=0.5, ролі=[], нитки=[])
        yield ('%s|%s|%s|%s|%s|%s|%s|%s|%s|%s' % (м, чк, ґр, кп, мо, ф, зона, слот, рух, рр), 'принт_придатність',
               [пал], dict(F=F[ф], масштаб_особи=мо, зона_камуфляж=зона, слот_принту=слот, рух=рух,
                           риси_рух=рр, річ_ім='блуза', річ_ід='ж-1'))
