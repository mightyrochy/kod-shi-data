# -*- coding: utf-8 -*-
"""K-SYS-08 / K-SYS-09 (стеля надлишку й підлога прісності) — підсумок двобічної
моделі якості перестав бути рядком у лозі.

ДО ПРАВКИ: обидва правила лишали РІВНО слід — `trace.запис` із трійкою
«провал / пройдено / без входу». Слід читає лог, знахідку читає людина, і
двобічна модель якості — єдине місце системи, яке судить образ ЯК ЦІЛЕ, а не по
одній речі, — не казала жінці нічого. Наряд тримав це в
`gate_reach.НА_ЗНАХІДКУ`: «підсумок чеклісту має виходити знахідкою над образом».
ПІСЛЯ: підсумок стоїть у `вердикт.образи[0].знахідки`, а знаменником частки є
пункти З ВХОДОМ — «без входу» не зараховується ні в чисельник, ні в знаменник,
інакше частка міряла б бідність фіду, а не образ."""
import sys, pathlib, json
_КОРІНЬ = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_КОРІНЬ))
import feed as Ф, bridge as B

вх = json.load(open(_КОРІНЬ / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
ід = [next(c for c in кат if c.get("слот") == сл)["id"] for сл in ("сукня", "взуття", "сумка")]
о = ((json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False))
      ).get("вердикт") or {}).get("образи") or [{}])[0]
ч = о.get("чекліст") or {}
зн = {z["правило"]: z for z in (о.get("знахідки") or [])}
for пр, бік in (("K-SYS-08", "надлишок"), ("K-SYS-09", "прісність")):
    п = ч.get(бік) or {}
    з_входом = len(п.get("провал") or []) + int(п.get("пройдено") or 0)
    print("%s · %s: провал %d / пройдено %d / без входу %d → знаменник %d"
          % (пр, бік, len(п.get("провал") or []), п.get("пройдено"),
             п.get("без_входу"), з_входом))
    z = зн.get(пр)
    print("   у вердикті:", "нема (пунктів із провалом нема)" if not z else
          "%s %.2f · %s · %s" % (z["сила"], z["сила_нп"], z["регістр"], z["суть"][:78]))
    if п.get("провал"):
        assert z, "%s: провалені пункти є, а підсумку у вердикті нема" % пр
        assert "%d із %d" % (len(п["провал"]), з_входом) in z["суть"], \
            "суть мусить називати частку від пунктів З ВХОДОМ, а не від усіх"
    else:
        assert not z, "%s: провалів нема, а рядок є" % пр
