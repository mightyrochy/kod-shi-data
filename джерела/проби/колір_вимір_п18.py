"""КОЛІР-ВИМІР-П18 (рядки 3120, 3123): що змінило правило «вимір, коли впевнений» на `каталог_повний` (рука 1).
ДО — те саме читання фіду з вимкненими `вимір_впевнений` (вимір поза вікном слова) і запобіжником світлого
майже нейтрального виміру у вікні (`СВІТЛЕ_L`). Друкує: скільки речей змінили колір, куди (вікно → точка /
точка → вікно), по слотах, і вибірку воріт — 40 змінених (сід 18): id, слово крамниці, колір ДО → ПІСЛЯ (hex).
Запуск із джерела/: python3 проби/колір_вимір_п18.py [сід]"""
import sys, random, collections as K
sys.path.insert(0, "."); import feed as F, фід_каталог as ФК, фід_збагачення as ФЗ, колір_річ as КР
import колір_простір_перетворення as П
F.каталог_на_диску("каталог_повний.xml")
def каталог():
    return {r["id"]: r for r in ФК._прочитати_каталог("каталог_повний.xml", 0)["каталог"]}
піс = каталог()
впевн, світле = ФЗ.вимір_впевнений, ФЗ.СВІТЛЕ_L
ФЗ.вимір_впевнений, ФЗ.СВІТЛЕ_L = (lambda *a: False), float("inf")
до = каталог()
ФЗ.вимір_впевнений, ФЗ.СВІТЛЕ_L = впевн, світле
вид = lambda r: "нема" if not r.get("lab") else "вікно" if КР.не_вимір(r) else "точка"
hx = lambda r: П.hex_з_lab(tuple(r["lab"])) if r.get("lab") else "—"
зм = sorted(і for і, r in піс.items() if і in до and tuple(до[і].get("lab") or ()) != tuple(r.get("lab") or ()))
print("речей:", len(піс), "змінили колір:", len(зм))
print("куди:", dict(K.Counter("%s → %s" % (вид(до[і]), вид(піс[і])) for і in зм)))
print("по слотах:", dict(K.Counter(піс[і].get("слот") for і in зм).most_common()))
rnd = random.Random(int(sys.argv[1]) if len(sys.argv) > 1 else 18); виб = list(зм); rnd.shuffle(виб)
for н, і in enumerate(виб[:40], 1):
    a, b = до[і], піс[і]; сл = (КР.не_вимір(a) or КР.не_вимір(b) or {}).get("слово", "")
    print("%2d %-30s %-11s крамниця «%s» %s %s → %s %s" % (н, і, b.get("слот"), сл, вид(a), hx(a), вид(b), hx(b)))
