"""Межа відповіді V4 і промпта розбору в токенах MamayLM (5.4-Г), без моделі: інваріант менеджера — найдовша
відповідь, яку пускає граматика, ≤ стеля − 10 %; найдовший промпт + стеля ≤ контекст слота.
python3 проби/межа_відповіді_54г.py <tokenizer.json>  (huggingface.co/INSAIT-Institute/MamayLM-Gemma-3-12B-IT-v1.0)
Цитата й фрагмент — знаками (кожен дозволений знак — один токен словника, перевіряє тут же); ключі й коди —
токенізатором, найдовший код кожного поля; пробіли JSON (SPACE_RULE llama.cpp, до 22 токенів) — лічбою місць."""
import json, re, statistics, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from tokenizers import Tokenizer
import каталог_розбір as КР, каталог_розбір_прогін as П, фід_каталог as ФК, фід_розбір as ФР
ТОК = Tokenizer.from_file(sys.argv[1])
т = lambda s: len(ТОК.encode(s, add_special_tokens=False).ids)
знаки = lambda кл: {chr(к) for а, б in re.findall(r"(.)-(.)", кл[:-1]) for к in range(ord(а), ord(б) + 1)} | set(re.sub(r".-.", "", кл[:-1])) | {кл[-1]}
поза = sorted(з for з in знаки(КР.ЗНАКИ_ЦИТАТИ) | знаки(КР.ЗНАКИ_ФРАГМЕНТА) if ТОК.token_to_id(з.replace(" ", "▁")) is None)
assert not поза, "знаки поза словником (по кілька токенів): %r" % поза
коди = 0
for ш, к, _ in КР._листки():
    ключ = КР._ключ_коду(ш) + "="
    if isinstance(к, КР.Мірка):
        коди += max([т(ключ + "9" * КР.цифр_мірки(к) + ".5 " + о + ";") for о in к.одиниці] + [т(ключ + с + ";") for с in к])
    else:
        один = max(т(ключ + с + ";") for с in (КР._без_тиші(к) if КР._кроки(ш)[0][1] else к)) - т(ключ + ";")
        пунктів = КР.СТЕЛІ_СПИСКІВ.get(КР._кроки(ш)[0][0], 1) if КР._кроки(ш)[0][1] else 1
        коди += т(ключ + ";") + пунктів * (один + 1)
ключ_доказу = max(т(ш + "=") for ш in КР.шляхи_доказів())
докази = КР.СТЕЛЯ_ДОКАЗІВ * (ключ_доказу + КР.СТЕЛЯ_ЦИТАТИ + 1)
фрагменти = КР.СТЕЛЯ_ФРАГМЕНТІВ * (КР.СТЕЛЯ_ЦИТАТИ + 1 + КР.СТЕЛЯ_ФРАГМЕНТА + 1)
обгортка, пробіли = т('{"evidence":"","codes":"","features":""}'), (2 + 3 * 3) * 22
межа = докази + коди + фрагменти + обгортка + пробіли
офери = ФР.читати_yml(ФК.каталог_на_диску(), показ=False)[0]
промпти = sorted(т(json.dumps(КР.промпт(o), ensure_ascii=False)) + 8 for o in офери)   # +8: шаблон Gemma 3
print("найдовша відповідь V4: %d токенів = докази %d (%d × ключ ≤%d + цитата %d) + коди %d + features %d + обгортка %d + пробіли %d"
      % (межа, докази, КР.СТЕЛЯ_ДОКАЗІВ, ключ_доказу, КР.СТЕЛЯ_ЦИТАТИ, коди, фрагменти, обгортка, пробіли))
print("промпт: речей %d · p50 %d · p99 %d · найдовший %d токенів" % (len(промпти), промпти[len(промпти) // 2], промпти[len(промпти) * 99 // 100], промпти[-1]))
С, К = П.МАКС_ТОКЕНІВ, getattr(П, "КОНТЕКСТ_СЛОТА", None)
print("стеля %d: межа ≤ 0.9·стелі (%d) — %s; промпт + стеля = %d ≤ контекст слота %s — %s"
      % (С, 0.9 * С, межа <= 0.9 * С, промпти[-1] + С, К, К is not None and промпти[-1] + С <= К))
