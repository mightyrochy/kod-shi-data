"""Межа відповіді V5 і промпта розбору в токенах MamayLM (5.4-Г), без моделі: інваріант менеджера — найдовша
відповідь, яку пускає граматика, ≤ стеля − 10 %; найдовший промпт + стеля ≤ контекст слота.
python3 проби/межа_відповіді_54г.py <tokenizer.json>  (huggingface.co/INSAIT-Institute/MamayLM-Gemma-3-12B-IT-v1.0)
Строга межа — ЗНАКАМИ: кожен знак, який пускає граматика, — окремий токен словника (перевіряє тут же), а токен має
хоч один знак, тож токенів не більше, ніж знаків, хай як модель розіб'є рядок. Поруч — канонічна токенізація
ключів і кодів. Пробіли JSON (SPACE_RULE llama.cpp, до 22 токенів) — лічбою місць: «{», кожен ключ, «:», значення,
«,», «}»."""
import json, re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from tokenizers import Tokenizer
import каталог_розбір as КР, каталог_розбір_прогін as П, фід_каталог as ФК, фід_розбір as ФР
ТОК = Tokenizer.from_file(sys.argv[1])
т = lambda s: len(ТОК.encode(s, add_special_tokens=False).ids)
знаки = lambda кл: {chr(к) for а, б in re.findall(r"(.)-(.)", кл[:-1]) for к in range(ord(а), ord(б) + 1)} | set(re.sub(r".-.", "", кл[:-1])) | {кл[-1]}
поза = sorted(з for з in знаки(КР.ЗНАКИ_ЦИТАТИ) | знаки(КР.ЗНАКИ_ФРАГМЕНТА) | set("abcdefghijklmnopqrstuvwxyz0123456789_.=;")
              if ТОК.token_to_id(з.replace(" ", "▁")) is None)
assert not поза, "знаки поза словником (по кілька токенів): %r" % поза
коди = lambda ш, к: ["9" * КР.цифр_мірки(к) + ".5 " + о for о in к.одиниці] if isinstance(к, КР.Мірка) else КР._коди_моделі(ш, к)
пункти = [";%s=%s=" % (КР._ключ_коду(ш), с) for ш, к, _ in КР._листки() if ш != КР.ТИП for с in коди(ш, к)]
типи = ["%s=%s=" % (КР.ТИП, с) for с in коди(КР.ТИП, КР.ПЕРЕЛІКИ[КР.ТИП])]
обгортка, ключів = '{"%s":"","%s":""}' % (КР.КОДИ, КР.ОСОБЛИВОСТІ), 2
пробіли = (1 + 3 * ключів + (ключів - 1) + 1) * 22
фрагменти = КР.СТЕЛЯ_ФРАГМЕНТІВ * (КР.СТЕЛЯ_ЦИТАТИ + 1 + КР.СТЕЛЯ_ФРАГМЕНТА) + КР.СТЕЛЯ_ФРАГМЕНТІВ - 1
межа = lambda м: (max(map(м, типи)) + КР.СТЕЛЯ_ЦИТАТИ + (КР.СТЕЛЯ_ПУНКТІВ - 1) * (max(map(м, пункти)) + КР.СТЕЛЯ_ЦИТАТИ)
                  + фрагменти + м(обгортка) + пробіли)
строга, канон = межа(len), межа(т)
assert re.fullmatch(КР.взірці()[КР.КОДИ], max(типи, key=len) + "ц" * 50 + (max(пункти, key=len) + "ц" * 50) * (КР.СТЕЛЯ_ПУНКТІВ - 1))
офери = ФР.читати_yml(ФК.каталог_на_диску(), показ=False)[0]
промпти = sorted(т(json.dumps(КР.промпт(o), ensure_ascii=False)) + 8 for o in офери)   # +8: шаблон Gemma 3
print("найдовша відповідь V5: строго %d токенів (знаками), канонічно %d = (тип ≤%d + %d × пункт ≤%d знаків, %s) + цитата %d кожен"
      " + features %d + обгортка %d + пробіли %d" % (строга, канон, max(map(len, типи)), КР.СТЕЛЯ_ПУНКТІВ - 1,
      max(map(len, пункти)), max(пункти, key=len), КР.СТЕЛЯ_ЦИТАТИ, фрагменти, len(обгортка), пробіли))
print("промпт: речей %d · p50 %d · p99 %d · найдовший %d токенів" % (len(промпти), промпти[len(промпти) // 2], промпти[len(промпти) * 99 // 100], промпти[-1]))
С, К = П.МАКС_ТОКЕНІВ, П.КОНТЕКСТ_СЛОТА
print("стеля %d: строга межа ≤ 0.9·стелі (%d) — %s; промпт + стеля = %d ≤ контекст слота %d — %s"
      % (С, 0.9 * С, строга <= 0.9 * С, промпти[-1] + С, К, промпти[-1] + С <= К))
