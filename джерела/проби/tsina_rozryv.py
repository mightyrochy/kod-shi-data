"""Рядок 45 БЕКЛОГ: п'ятикратний ціновий розрив в одному образі (сукня 6999 ₴ /
мюлі 37400 ₴ на живій сторінці). У корпусі й коді нема правила «зв'язність ціни
ОБРАЗУ» — є лише K-PRC-01/02 (`accessory.цінність_речей`), а це ранг речі СЕРЕД
РЕЧЕЙ ТОГО Ж СЛОТА В ПУЛІ (чи дешева ця сукня проти інших суконь), а не проти
пари в тому самому образі. Синтетичний образ на реальному каталозі: сукня і
взуття з розривом ≈5x, узятi так, щоб взуття НЕ було топ-чвертю СЕРЕД ВЗУТТЯ
(інакше спрацювання було б випадковим збігом, не доказом зв'язності). Запуск з
теки `джерела`: `python3 проби/tsina_rozryv.py`."""
import sys, pathlib, json
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
import feed as Ф, bridge as B

вх = json.load(open("стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх["гілка"] = 0
з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
пак = [p for p in B._КЕШ_ПАКЕТА.values() if p.get("_цінність", {}).get("є")][0]
кат = {c["id"]: c for c in пак["_каталог"]}
пул = [кат[r["id"]] for п in з["кандидати"].values() for r in п if r["id"] in кат]
сукні = sorted([c for c in пул if c["слот"] == "сукня" and c.get("ціна")], key=lambda c: c["ціна"])
взуття = [c for c in пул if c["слот"] == "взуття" and c.get("ціна")]
пара = next((д, вз) for д in сукні for вз in взуття
            if 4.8 <= вз["ціна"] / д["ціна"] <= 5.5 and (вз.get("ціна_ранг") or 1) < 0.75)
дешева, дороге = пара

судити = lambda ід: (((json.loads(B.виклик("від_моделі", json.dumps(dict(вх, ід=ід), ensure_ascii=False))
    ).get("вердикт") or {}).get("образи") or [{}])[0].get("знахідки") or [])
зн = судити([дешева["id"], дороге["id"]])
за_правилом = {z["правило"]: z for z in зн}
print("образ: сукня %d ₴ (ранг %.2f) · взуття %d ₴ (ранг %.2f) · розрив %.2fx"
      % (дешева["ціна"], дешева.get("ціна_ранг") or 0, дороге["ціна"],
         дороге.get("ціна_ранг") or 0, дороге["ціна"] / дешева["ціна"]))
print("усі знахідки образу:", sorted(за_правилом))
if "K-PRC-01" in за_правилом:
    z = за_правилом["K-PRC-01"]
    print("K-PRC-01:", z["сила"], "%.2f" % (z.get("сила_нп") or 0), z.get("регістр"), "·", z["суть"][:90])
else:
    print("K-PRC-01: НЕМА ЗНАХІДКИ — розрив між РЕЧАМИ образу нікому не названо;"
          " правило мовчить, бо взуття не топ-чверть СЕРЕД ВЗУТТЯ, а не тому, що дешеве проти сукні")
