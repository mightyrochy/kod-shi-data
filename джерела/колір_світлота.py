# є), тому вона невиміряний елемент пропускає й пише це у себе; `нейтралі_крос` у
# секції нижче зробила той самий вибір окремим рішенням (07.09.2026) і лишається при
# ньому — на живому шляху та гілка недосяжна, бо `review` утримує K-COL-06 разом із
# рештою чотирьох, і переписувати її означало б змінити вердикт правила поза межами
# цього наряду.
#
# ЦІНА НАЗВАНА: на ЧАСТКОВО виміряному образі ці правила судили б підмножину речей.
# Щоб це не стало мовчазним режимом, `перевірити_контракт` окремо стежить, що
# площозалежна знахідка не вийшла, поки в стані лишився елемент без площі.
def value_структура(E):
    """K-COL-01. Скільки виразних кроків світлоти несе образ.
    Крок = група речей, розділена від сусідньої на ≥ step_min по L*.
    Дрібні елементи (< min_area) у структуру не входять — вони акценти, не поверхи."""
    осн = sorted(_з_площею(E, C["min_area"]), key=lambda e: e["L"])
    if not осн: return None
    кроки = [[осн[0]]]
    for e in осн[1:]:
        (кроки.append([e]) if e["L"] - кроки[-1][-1]["L"] >= C["step_min"] else кроки[-1].append(e))
    опис = [dict(L=round(sum(x["L"] for x in g)/len(g),1),
                 площа=round(sum(x["площа"] for x in g),2),
                 речі=[x["річ"] for x in g]) for g in кроки]
    вагомі = [k for k in опис if k["площа"] >= 0.12]
    return dict(кроків=len(кроки), вагомих=len(вагомі), кроки=опис,
                текстур=len({e["текстура"] for e in осн if e["текстура"]}))

