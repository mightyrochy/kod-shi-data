# а не робочий режим.
#
# ЧОМУ НЕ «пропускається до правила». Тут площа — САМА УМОВА УЧАСТІ: крок світлоти,
# бюджет гучних, лічба сімей, група відлуння. Пропустити елемент без площі означало б
# сказати «його площа достатня», чого ми не знаємо, — та сама вигадка, лише з іншим
# знаком. МЕЖА ПОЛІТИКИ названа: `біля_обличчя` у цій самій секції площі не потребує
