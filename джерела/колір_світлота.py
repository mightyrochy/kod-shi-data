# ── ОДНА ПОЛІТИКА НА НЕВИМІРЯНУ ПЛОЩУ: УТРИМУЄТЬСЯ (Н-outfit-1-084) ──────────
# `елементи()` прямо каже: «area = r.get("площа") — None = не виміряно; не
# підставляється нічим». Пʼять функцій цієї секції читали цей ДОКУМЕНТОВАНИЙ стан
# трьома різними способами, тобто політики не було:
#   · `value_структура` і `сім_ї_образу` — падали TypeError на `None >= float`;
#   · `бюджет_хроми` — мовчки підставляв `or 0`, тобто вигадував нуль (рівно те,
#     чого модуль собі не дозволяє в жодній знахідці);
#   · `відлуння` — робило і те, й те: групувало через `or 0`, а потім падало на
#     `sum(None)`, тобто іншим винятком за той самий стан.
#
# ПОЛІТИКА (одна на всі пʼять): НЕВИМІРЯНА ПЛОЩА НЕ ПІДСТАВЛЯЄТЬСЯ ЧИСЛОМ І НЕ
# ПРОХОДИТЬ ПОРОГУ. Елемент без площі до площозалежного рішення НЕ ВХОДИТЬ
# (`_з_площею`), і хто не ввійшов — НАЗИВАЄТЬСЯ (`_без_площі`), а не зникає мовчки.
# ДЕ САМЕ НАЗИВАЄТЬСЯ: на живому шляху — знахідкою `_утримано_без_площ` у `review`
# (вона перелічує всі невиміряні речі й несе `покриття_входу`); при прямому виклику
# правила, яке все одно може щось винести, — його власною знахідкою «утримано»
# (K-COL-02 про пари без площі, K-COL-05 про речі, що не ввійшли в групування).
# Вище рівнем `review` робить те саме радикальніше: коли площі не виміряні, усі пʼять
# правил не виносяться взагалі (реєстр `ПЛОЩОЗАЛЕЖНІ`), тож усередині функцій цей
# шлях — ЗАХИСТ на випадок прямого виклику (composer і прилади кладуть свої dict-и),
# а не робочий режим.
#
# ЧОМУ НЕ «пропускається до правила». Тут площа — САМА УМОВА УЧАСТІ: крок світлоти,
# бюджет гучних, лічба сімей, група відлуння. Пропустити елемент без площі означало б
# сказати «його площа достатня», чого ми не знаємо, — та сама вигадка, лише з іншим
# знаком. МЕЖА ПОЛІТИКИ названа: `біля_обличчя` у цій самій секції площі не потребує
# (умова участі там — приобличчева вага, а поріг площі лише відсіює дрібне, КОЛИ вимір
# є), тому вона невиміряний елемент пропускає й пише це у себе; `нейтралі_крос` у
# секції нижче робить той самий вибір окремо й лишається при
# ньому — на живому шляху та гілка недосяжна, бо `review` утримує K-COL-06 разом із
# рештою чотирьох, і переписувати її означало б змінити вердикт правила поза межами
# цього наряду.
#
# ЦІНА НАЗВАНА: на ЧАСТКОВО виміряному образі ці правила судили б підмножину речей.
# Щоб це не стало мовчазним режимом, `перевірити_контракт` окремо стежить, що
# площозалежна знахідка не вийшла, поки в стані лишився елемент без площі.
МАКС_РІВНІВ_СВІТЛОТИ = 3   # K-COL-01 (тема-4): «2–3 окремі кроки світлоти»; більше — value-шум


def value_структура(E):
    """K-COL-01. Скільки виразних кроків світлоти несе образ.
    Крок = група речей, розділена від сусідньої на ≥ step_min по L*.
    Дрібні елементи (< min_area) у структуру не входять — вони акценти, не поверхи."""
    # Участь за площею — відповідь «≥ min_area» (`частка_понад`). Частка будь-якого джерела без похибки обох
    # боків дає «невідомо»: така річ лишається кандидатом поверху (як у ланцюжку біля обличчя), і її ім'я
    # стоїть у `участь_невідома`; ні вагомим, ні легким її крок не стає. Невиміряна площа (None) — поза
    # структурою, як і доти.
    осн = sorted([e for e in E if частка_понад(e, C["min_area"]) in ("так", НЕВІДОМО_ЧАСТКИ)],
                 key=lambda e: e["L"])
    if not осн: return None
    кроки = [[осн[0]]]
    for e in осн[1:]:
        (кроки.append([e]) if e["L"] - кроки[-1][-1]["L"] >= C["step_min"] else кроки[-1].append(e))
    опис = [dict(L=round(sum(x["L"] for x in g)/len(g),1),
                 площа=round(sum(x["площа"] for x in g),2), площа_межі=межі_суми(g),
                 речі=[x["річ"] for x in g]) for g in кроки]
    # ВАГОМИЙ КРОК — ВІДПОВІДЬ «≥ 0.12» НАД МЕЖАМИ СУМИ ЧАСТОК КРОКУ (`частка_понад`): «невідомо»
    # не стає ні вагомим, ні легким — його лічить `вагомих_можливо`, і вирок K-COL-01 на ньому не стоїть
    for k in опис:
        k["вагомий"] = частка_понад(k, 0.12)
    return dict(кроків=len(кроки), вагомих=sum(k["вагомий"] == "так" for k in опис),
                вагомих_можливо=sum(k["вагомий"] == НЕВІДОМО_ЧАСТКИ for k in опис), кроки=опис,
                текстур=len({e["текстура"] for e in осн if e["текстура"]}),
                участь_невідома=sorted({e["річ"] for e in осн
                                        if частка_понад(e, C["min_area"]) == НЕВІДОМО_ЧАСТКИ}) or None)

def перевірка_value(E, intent=None, мета=None, вище=False):
    """Знахідки K-COL-01 (структура світлоти образу) над елементами з площею ≥ `C["min_area"]`: одна
    вагома поверхня → «утримано»; один рівень (усі речі в межах `C["step_min"]`) → strong «площинно»
    з ремонтом і запитом на другий крок; чотири й більше
    рівнів → soft «value-шум», гейтований наміром.

    Чому так: структура світлоти — властивість ≥2 вагомих поверхонь, на одній її нема
    (фейл-кейс stolyarchuk: гейт блокував усі сукні). Самої присутності верхнього шару
    недостатньо, щоб стверджувати, що він довгий і відкритий, та послаблювати знахідку.

    ── МЕТА «ВИЩЕ»: КОЛОНА ПЕРЕМАГАЄ «ПЛАСКО» ──
    Звіт Research назвав це конфліктом двох правил, а не помилкою: колона в один тон і
    темний низ мають рівні C/B на користь вертикалі, а K-COL-01 рахує той самий образ
    вадою «пласко». Власник вирішив, хто сильніший і за якої мети: КОЛИ ЖІНКА
    ПОПРОСИЛА ДОВШОЇ ЛІНІЇ («вище»), однотонна колона з голови до ніг перемагає —
    «площинно» не виходить зовсім, а замість неї виходить hint «лишити»: колона і є
    той механізм, про який вона просила. Для решти мет вердикт про один рівень світлоти
    лишається без послаблення за невідомим розкладом шарів.
    ЧОМУ HINT, А НЕ ТИША. Тиша була б невідрізнима від «перевірено й чисто» — рівно
    те, що проєкт забороняє. Форма hint-бонусу тут та сама, що в R-PRN-04 («відлуння
    форми … лишити»): знахідка говорить, нічого не блокує, і мовна модель має що
    сказати жінці замість безадресної похвали."""
    # Невідома участь хоча б однієї речі не дає судити підмножину як увесь образ.
    if площа_невідома(E, C["min_area"]):
        return перевірка_value_за_слотом(E, intent, мета, вище)
    осн = з_площею(E, C["min_area"])
    if not осн: return []
    out = []
    # ── КРОКИ РАХУЮТЬСЯ ЛИШЕ НА ВИМІРАХ ──
    # Елемент із кольором зі слова несе смугу світлоти, а не точку: L* у нього None (`outfit.елементи`),
    # і `value_структура`, що сортує за L*, на ньому не рахується. Доти рахувалась — центром вікна.
    # Одна поверхня одного кольору — один рівень і без виміру; решту з вікнами судить гілка нижче.
    _невим = [e for e in осн if не_вимір(e)]
    vs = None if _невим else value_структура(E)
    if vs and vs["вагомих_можливо"]:
        # вагомість кроку — «невідомо» (межі суми часток перетинають 0.12): лічба вагомих рівнів
        # стояла б на ній — те саме утримання без виміру частки, що й вище
        return перевірка_value_за_слотом(E, intent, мета, вище)
    n = vs["кроків"] if vs else None
    if vs:
        осн = sorted(осн, key=lambda e: e["L"])
    розмах_L = (осн[-1]["L"] - осн[0]["L"]) if vs else None
    # ── ОДНА ВАГОМА ПОВЕРХНЯ = НЕМА СТРУКТУРИ, ЯКУ МОЖНА СУДИТИ ──
    # Фейл-кейс stolyarchuk (24 сукні, взуття у фіді нема): кожна сукня САМА є одним
    # рівнем світлоти за визначенням, і K-COL-01 як гейт блокував усі 5/5 кандидатів
    # обох колоритів («чистих 0») — гейт із найкращим доказом системи судив вхід, якого
    # не існує. Структура світлоти — властивість ≥2 вагомих поверхонь; на одній вона
    # утримується, а замість неї говорить K-SIL-09: сукня (одна річ) — моно-об'єкт,
    # образ «одягнений, не стилізований», третя річ майже обов'язкова (тема-4 Part V,
    # strong [convention] → стеля T3 = soft; репліка, не гейт).
    вагомих_речей = {e["річ"] for e in осн}
    if len(вагомих_речей) == 1 and (n == 1 if vs else len(осн) == 1):
        річ = next(iter(вагомих_речей))
        e1 = осн[0]
        out.append(_зн(
            правило="K-COL-01",
            сила="утримано",
            суть="одна вагома поверхня — структура світлоти між речами не існує; K-COL-01 утримано",
            заяви=[_ВМ.заява("one_weighty_surface")],
            речі=[річ],
            чому="в образі одна річ з площею ≥ %.2f; крок світлоти — це відношення між "
                 "речами, і судити його на одній нема з чого" % C["min_area"],
            примітка="виміру нема (утримано): структура світлоти потребує ≥2 вагомих поверхонь"))
        # `trace.запис` лише додає запис у список і не падає;
        # обгортка ховала б помилку цих двох рядків, а не «збій сліду».
        _СЛ.запис("K-COL-01", "held_one_heavy_surface", "перевірка_value",
                  значення="речей %d" % len(вагомих_речей), сила=None, напрям="гейт → утримано")
        # ── K-SIL-09 НАЛЕЖИТЬ `суд_образу.мономісце` ───────────────────────
        # Тут стояла його емісія — і стояла ЗА ГЕЙТОМ ПЛОЩ: цю гілку `review`
        # виносить лише коли КОЖНА річ образу несе `джерело_площі`, а воно
        # ставиться тільки з виміряних країв (`outfit.площі_з_геометрії` —
        # «все або нічого»; сумка й прикраси країв не мають зовсім). На живому
        # шляху покриття нульове, тож правило утримувалось разом із п'ятьма
        # колірними — хоч площа йому не потрібна: його WHEN дослівно каже
        # «єдина велика поверхня образу це сукня (або одна річ)», тобто факт
        # СЛОТА. Емісія тепер у `суд_образу.мономісце`, за слотами, і текст,
        # ремонт і запит переїхали туди без зміни. Тут лишається сам
        # `K-COL-01 утримано` — це справді про площу.
        return out
    # ── КРОКИ СВІТЛОТИ МІЖ ПОВЕРХНЯМИ — ЛИШЕ НА ВИМІРІ ──
    # Крок — ΔL* між двома поверхнями, а колір зі слова — смуга світлоти вікна,
    # не точка: «один рівень» чи «шум» над центрами вікон був би наслідком
    # побудови. Коли серед вагомих поверхонь є колір, що не вимір, висновок
    # стоїть, лише якщо його дають межі вікон: два рівні напевно (зазор між
    # вікнами ≥ кроку) і вагомих поверхонь менше чотирьох — ні площинності, ні
    # шуму бути не може, правило законно мовчить; інакше — «без входу».
    # «Два рівні напевно» — клас `value_step` API відношень (КОЛІР-Р4).
    if _невим:
        _два_рівні = any(відношення(a, b, "value_step") == "так"
                         for i, a in enumerate(осн) for b in осн[i + 1:])
        if _два_рівні and len(вагомих_речей) < 4:
            return out
        return out + [без_входу_кольору(
            "K-COL-01", [(e,) for e in _невим],
            перевірка="cannot_tell_lightness_structure")]
    if n == 1 and вище:     # «довша лінія» — друга вісь мети (`мета_важливо`)
        # «10 а»: її слова про довшу лінію сильніші за правило площинності. Умова —
        # рівно «колона»: один рівень світлоти (`n == 1`) на ≥2 вагомих поверхнях
        # (гілку однієї поверхні вище ця не бачить — там структури не існує).
        # Відкритий шар тут не потрібен: власник сказав «з голови до ніг», тобто
        # умова — сам тон, а не спосіб носіння.
        # ОПОРА, НЕ ЗАУВАЖЕННЯ: «лишити» не має бути знахідкою `hint` з вагою —
        # інакше ремонт читав би похвалу як зауваження. Це опора образу: ваги й ремонту нема,
        # учасники — вагомі поверхні колони; ремонт дістає її в `keep`, вибір — у `lost_supports`.
        _колона = [r for k in vs["кроки"] for r in k["речі"]]
        out.append(_зн("K-COL-01", "hint",
            "один тон із голови до ніг — це колона, і саме її ти просила: лишити",
            _колона,
            "мета цього виходу — довша лінія («вище»), а колона в один тон і є той "
            "механізм: усі вагомі поверхні в межах ΔL*<%.0f, вертикаль не розбита"
            % C["step_min"],
            заяви=[_ВМ.заява("column_one_tone_is_her_goal", surfaces=int(vs["вагомих"]))],
            ламається="напрям тут стоїть на ЇЇ СЛОВАХ, не на вимірі: сила вертикалі "
                      "проти площинності не калібрована ні в один бік (звіт Research: "
                      "колона й темний низ — C/B, площинність — те саме). Тому це опора, "
                      "а не вимога; без мети «вище» правило судить як доти",
            примітка="K-SIL-04/K-SIL-07: колона — механізм подовження; тут він не "
                     "послаблює вердикт, а заміняє його, бо мета названа жінкою",
            полярність=ОПОРА, учасники=[dict(роль="column", річ=r) for r in _колона]))
        out[-1]["також_правила"] = ["K-SIL-07", "K-SIL-04"]
        _СЛ.запис("K-COL-01", "goal_taller_column_beats_flatness",
                  "перевірка_value", значення="вагомих поверхонь %d" % vs["вагомих"],
                  сила=0.0, напрям="вада → опора")
    elif n == 1:
        різні_мітки = vs["текстур"] >= 2
        # Корпус дозволяє рятувати площинність текстурою — але КОНТРАСТ текстур модуль
        # не вимірює (мітки типу smooth-matte/leather не кажуть, чи вони видимо різні).
        # Тому сила не знижується автоматично: різні мітки лише додають умову перевірки.
        out.append(_зн("K-COL-01", "strong",
            "один рівень світлоти — образ читається площинно",
            [r for k in vs["кроки"] for r in k["речі"]],
            f"усі речі в межах ΔL*<{C['step_min']:.0f}; тон-у-тон без кроків",
            ремонт=([f"спертись на текстурний контраст — мітки текстур різні ({vs['текстур']}), але їх видиму "
                     "різницю модуль не вимірює: рішення візуальне"] if різні_мітки else None),
            заяви=[_ВМ.заява("one_lightness_level_reads_flat", spread=round(розмах_L, 1),
                             step_min=round(C["step_min"]))],
            ремонт_заяви=([_ВМ.заява("or_lean_on_texture_contrast", textures=int(vs["текстур"]))]
                          if різні_мітки else None),
            запит=dict(слот="взуття|сумка|верхній_шар",
                 цільова_L=[round(vs["кроки"][0]["L"]+18), round(min(95, vs["кроки"][0]["L"]+40))],
                 чому="другий крок світлоти"),
            ламається="монохромна колона — свідомий хід (подовження, K-SIL-07): "
                      "тоді площинність не дефект, а мета; правило вимкнути через intent",
            # ЗНАЙДЕНО audit_неперервність: вимір тут не передавався взагалі, тож
            # сила падала в категорію і дорівнювала 0.75 НА БУДЬ-ЯКОМУ площинному образі
            # — і це на єдиному правилі-гейті системи, яке стоїть на єдиній константі
            # тіру T2 (крок Munsell Value). Правило з найкращим доказом мало найгіршу
            # неперервність. Вимір був поруч: РОЗМАХ L* усередині єдиного кроку.
            # 0 = ідеально площинно (сила 1.0), ближче до step_min = майже два кроки.
            # РОЗКИД ЗОН: річ — зона, не точка. Колір зі
            # слова несе півширину L-вікна («сірий» ±27.5), фото — розкид пікселів;
            # коли маржа тонша за точність, вердикт гаситься — «площинно» над двома
            # словами сірого не стверджується з силою виміру.
            вимір=розмах_L, поріг=C["step_min"], повна=C["step_min"],
            розкид=розкид(*[e for k in vs["кроки"] for e in E if e.get("річ") in k["речі"]])))
        # Запис місця називає видимість, але не відкритість і довжину шару.
        # Самої присутності речей під ним для послаблення K-SIL-07 недостатньо.
    elif vs["вагомих"] > МАКС_РІВНІВ_СВІТЛОТИ:
        out.append(_гейт_наміром(_зн("K-COL-01", "soft", "чотири і більше вагомих рівнів світлоти — value-шум",
            [r for k in vs["кроки"] if k["вагомий"] == "так" for r in k["речі"]],
            "жоден рівень не домінує; око не знаходить структури",
            вимір=float(vs["вагомих"]),   # було: len(рівні) if "рівні" in dir() — змінної
                                          # `рівні` у функції нема, вираз завжди давав None,
                                          # тож сила_нп падала в «категорія (виміру немає)»
            ламається="принтована річ сама дає кілька рівнів — тоді рахувати її як один",
            # ПОРІГ І УМОВА ЗБІГАЮТЬСЯ НАВМИСНО, і це коштувало правилу першого
            # випадку (Н-outfit-1-089). Умова `>= 4` нестрога, тож при РІВНО
            # чотирьох рівнях маржа нульова — і вага виходила 0.0, тобто правило
            # спрацьовувало й одразу гинуло під підлогою сили. Зсувати поріг на 3
            # означало б збрехати про те, що правило міряє («чотири і більше»), і
            # дати рівно чотирьом вагу цілого зайвого рівня. Тому полагоджено
            # шкалу, а не число: маржа рівно на порозі віддає підлогу, не нуль
            # (див. `_неперервна_сила`). Рампа: 4 рівні → 0.05, 5 → 0.25, 6 → 0.50.
            поріг=4), intent))
    return out

