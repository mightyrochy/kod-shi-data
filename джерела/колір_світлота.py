def перевірка_value_за_слотом(E, _intent=None, _мета=None, _вище=False):
    """Утримує K-COL-01 без виміряної похибки частки, зокрема для класу слота.

    Таблиця слотів не є виміром площі. Параметри сім'ї збережено для викликачів;
    намір і мета не додають відсутнього виміру.
    """
    return [утримано_площа_невідома("K-COL-01", E)] if E else []


def цільове_вікно(L_шкіри, gap_особи, темніша=True, важіль=0.0):
    """Вікно L*, у якому річ біля обличчя дає стрибок у межах контрасту особи.
    Це і є фільтр у каталог: не «візьміть щось світліше», а числовий діапазон.
    Двобічне: річ може бути темнішою або світлішою за обличчя — обидві гілки легітимні.
    `важіль` — крок K-CLR-03 від помітного макіяжу (`face_contrast.дозволений_контраст`):
    він розсуває лише ДАЛЬНІЙ край (стелю), ближній край від власного контрасту
    не рухається — ширина вікна росте рівно на важіль."""
    lo_gap = максимум0(gap_особи - C["under"]); hi_gap = gap_особи + float(важіль or 0.0) + C["over"]
    if темніша:
        return [round(max(0, L_шкіри - hi_gap)), round(max(0, L_шкіри - lo_gap))]
    return [round(min(100, L_шкіри + lo_gap)), round(min(100, L_шкіри + hi_gap))]

# ── ЧАСТКА ПЛОЩІ: ПОХИБКА ЖОДНОГО ДЖЕРЕЛА НЕ ВСТАНОВЛЕНА ──
НЕВІДОМО_ЧАСТКИ = "невідомо"


def межі_частки(e):
    """Наявна частка без виміряної похибки — «невідомо», відсутня — None.

    Жоден писач частки (геометрія, маски фото, клас слота, ручний ввід) не дає
    похибки обох боків. Межі агрегату не стають виміром через підсумовування.
    """
    if "площа_межі" in e:
        return None if e["площа_межі"] is None else НЕВІДОМО_ЧАСТКИ
    return None if e.get("площа") is None else НЕВІДОМО_ЧАСТКИ


def межі_суми(члени):
    """Сума не має відомих меж, якщо їх не має жодне джерело частки."""
    return None if any(межі_частки(e) is None for e in члени) else НЕВІДОМО_ЧАСТКИ


def частка_понад(e, _поріг):
    """Відповідь про поріг: «невідомо» без похибки, None без частки.

    Параметр порога лишається в API правил; жодне джерело частки зараз не має
    виміряної похибки, тому числове порівняння не обґрунтоване.
    """
    return межі_частки(e)


def утримано_площа_невідома(правило, елементи):
    """Знахідка «утримано» (вага нуль) площозалежного правила, коли частка площі речей — із
    будь-якого джерела без похибки обох боків (`площа_невідома`): відповіді «≥ поріг» код не знає, тож вироку
    нема, а не вирок над рештою речей. Чисел частки моделі не дає — це оцінка крізь крок, не вимір
    (рішення 06.11 «факт замість межі», п.3)."""
    речі = sorted({e.get("річ") or e.get("id") for e in елементи})
    заяви = [_ВМ.заява("area_share_error_unknown")]
    return _зн(правило=правило, сила="утримано", суть=_ВМ.суть_кодом(заяви, речі), заяви=заяви,
               речі=речі,
               чому="для джерела частки площі цих речей похибки обох боків код не знає, тож "
                    "відповіді «площа ≥ поріг» нема",
               примітка="виміру нема (утримано): частка площі не встановлена над похибкою обох боків")


def з_площею(E, поріг):
    """Елементи, чия площа ВИМІРЯНА і напевно досягає порога (`частка_понад` «так») — єдина
    форма участі у площозалежному рішенні (політика вгорі секції). Невиміряна площа не стає
    нулем і не стає «достатньою»; площа з кроку геометрії без похибки обох боків — теж:
    елемент просто не входить, і його називає `без_площі(E, поріг)`."""
    return [e for e in E if частка_понад(e, поріг) == "так"]


def без_площі(E, поріг=None):
    """Елементи, яких площозалежне рішення не порахувало: площа не виміряна, а з порогом — ще й
    ті, чию відповідь «≥ поріг» код не знає (`частка_понад` «невідомо»). Їх називають у знахідці —
    у цьому вся різниця між утриманням і мовчанням."""
    return [e for e in E if e.get("площа") is None
            or (поріг is not None and частка_понад(e, поріг) == НЕВІДОМО_ЧАСТКИ)]


def площа_невідома(E, поріг):
    """Елементи з виміряною площею, чию відповідь «≥ поріг» код не знає (джерело без похибки
    обох боків): на них площозалежний вердикт не стоїть — правило утримується."""
    return [e for e in E if e.get("площа") is not None and частка_понад(e, поріг) == НЕВІДОМО_ЧАСТКИ]


def розкид(*елементи):
    """Найгірший розкид серед зон, що беруть участь у рішенні. None, якщо жодна
    з них розкиду не несе (геометричний шлях, синтетика, ручний ввід)."""
    r = [e.get("розкид") for e in елементи if isinstance(e, dict) and e.get("розкид")]
    return max(r) if r else None

def гейт_контрасту(зн, особа):
    """R-PC-10: вісь контрасту утримана гейтом (регіональний шум профілю з фото
    `se_L` перевищує те, що вісь розрізняє) — сила K-CLR-02 сходить на крок від
    ВЖЕ ЗРІЗАНОЇ (стеля тіру T3 = soft ставиться в `_зн`, тож крок до емісії був би
    невидимий), вага ріжеться до стелі нової категорії тим самим `обмежити_вагу`, що
    й у гейті наміру; знахідка лишається з числом. Без виміру шуму (hex-ввід) — без
    змін: сила не зростає. Сила, регістр, слово й вага — єдиним шляхом `перезважити`
    (Е3-сила-правила), як еластан: реєстр той самий, що в `_зн` емісії (ядра)."""
    К = особа.get("надійність_контрасту") or {}
    if (К.get("регіональний_шум") is None or К.get("надійність", 1.0) >= MIN_TO_EMIT
            or зн.get("сила") not in ПОРЯДОК):
        return зн
    i = min(ПОРЯДОК.index(зн["сила"]) + 1, len(ПОРЯДОК) - 1)
    зн = dict(зн, примітка=((зн.get("примітка") + "; ") if зн.get("примітка") else "")
                          + f"вісь контрасту утримана гейтом ({К['чому']}) — знижено на крок")
    return перезважити(зн, ПОРЯДОК[i])

def _задум_мисматчу(зн, мисматч, L_шк, Δ_мк, лише_задум=False):
    """Та сама знахідка K-CLR-02, але як СВІДОМИЙ ЗАДУМ жінки.

    ЩО ЦЕ МІНЯЄ В РІШЕННІ. before: жінка обирала на екрані палітри гілку
    «контраст-мисматч» — тобто ПРОСИЛА контраст образу не під свій власний, — а
    суд за це ж її і сварив: «одяг носить людину, обличчя стирається», з ремонтом
    «замінити верх» і запитом у каталог, який тягнув пул назад до матчу. Продукт
    виконував прохання й тут-таки називав його дефектом.
    after: вимір лишається недоторканим — `сила`, `сила_нп`, `вимір`, `поріг`,
    `розкид`, ланцюг і числа ті самі, бо правило НЕ послаблене: воно й далі міряє
    стрибок проти ВЛАСНОГО контрасту особи. Міняється те, що читає людина: суть
    названа задумом без ремонту й запиту в каталог. Пропозиція заміни потребує
    кандидатів добору й повного суду; проти цього задуму виходить лише пояснення.

    `свідомий` — те саме поле, яким система вже позначає оголошений хід моделі
    (`pipeline._застосувати_свідомі`, `повнота_образу`, `вердикт_моделі`: «←
    оголошений хід»). Другий писар у нього — тут, і пише він не здогад, а ВИБІР
    ЖІНКИ; нового слова в протоколі для цього не заводиться (`знахідка.РЕГІСТРИ`
    лишаються трьома), бо задум — властивість походження знахідки, а не її
    регістру.

    `лише_задум` — для підказки «світле біля глибокої шкіри»
    (аудит/ПРОДУКТ.md п.18): вона не просить ні ремонту, ні запиту в каталог, і мисматч
    цього не міняє — знахідка дістає тільки `свідомий` і `задум`, суть і заява
    лишаються її власні. Доти (ж4, білий верх #f4f4f0): без мисматчу hint без
    ремонту й запиту, з мисматчем — hint із ремонтом і `запит_у_каталог`."""
    м = мисматч
    # Драбина — у фізичних L* біля шкіри (`драбина`); рівні — від міри рівня особи
    # (`палітра_схеми.зсув_мисматчу`). Старий вихід без `драбина` — та сама міра.
    задум = dict(гілка=м.get("гілка"), базова=м.get("базова"), власний=м["власний"],
                 підставлений=м["підставлений"], рівень_власний=м["рівень_власний"],
                 рівень_образу=м["рівень_образу"],
                 драбина_власна=float(м.get("драбина_власна", м["власний"])),
                 драбина=float(м.get("драбина", м["підставлений"])),
                 вироджено=м.get("вироджено"))
    if лише_задум:
        return dict(зн, свідомий=м["чому"], задум=задум)
    др, др_вл = задум["драбина"], задум["драбина_власна"]
    суть = ("контраст образу свідомо не під твій власний — це обрана схема, не промах: "
            "драбина світлоти стоїть на %.1f L* (%s) замість власних %.1f L* (%s)"
            % (др, м["рівень_образу"], др_вл, м["рівень_власний"]))
    # `для_стиліста` РАХУЄТЬСЯ ЗАНОВО, а не лишається від конструктора: `_зн` зліпив
    # його з ПОПЕРЕДНЬОЇ суті, і саме цей рядок читає модель. Підмінити суть і
    # лишити стару репліку означало б сказати жінці задум, а моделі — докір.
    зн = dict(зн, суть=суть, свідомий=м["чому"],
              для_стиліста=_репліка(суть, зн.get("чому") or ""),
              задум=задум)
    for поле in ("ремонт", "ремонт_заяви", "запит_у_каталог"):
        зн.pop(поле, None)
    if м.get("вироджено"):
        зн["примітка"] = ((зн.get("примітка") + "; ") if зн.get("примітка") else "") + м["вироджено"]
    return зн


def _метал_зі_слова(e):
    """True — елемент є прикрасою, чий колір знає лише слово металу («золотий» на фото з бордовою
    вставкою): такий колір — матеріал, не кольорова поверхня ланцюга біля обличчя.
    Її судить метал і блиск (запит K-CLR-02 називає метал інструментом цієї осі), а колір вставки
    йде в ланцюг лише з виміру: вимір і колір, що не слово металу, лишаються в ланцюзі."""
    return не_вимір(e) is not None and _PL.колір_металу(e)


def біля_обличчя(E, особа, мисматч=None):
    """K-CLR-02 + K-CLR-03. Порівнюється НЕ загальний контраст образу, а стрибок
    світлоти у зоні обличчя — з контрастом, який особа несе сама.
    Рахується МАКСИМАЛЬНИЙ СУСІДНІЙ розрив у ланцюжку
    {шкіра} ∪ {речі біля обличчя}, а не повний розмах. Тому шарф проміжної світлоти
    справді лікує: він розбиває один стрибок на два менші. Це не окремий бонус —
    це той самий вимір.

    `мисматч` — зсув драбини (`палітра_схеми.зсув_мисматчу` через
    `палітра_специфікація.поверхи`), коли жінка обрала гілку «контраст-мисматч».
    Правило від цього НЕ слабшає: ліміт, поріг, вимір і сила рахуються з її
    ВЛАСНОГО контрасту, як і доти. Міняється лише те, ЧИМ виходить знахідка, що
    порушення й було задумом, — див. `_задум_мисматчу`."""
    if not особа.get("доступно"): return []
    # ── ТОЙ САМИЙ ЛІМІТ, ЩО В РАНЗІ ОСНОВ І У ВІКНІ `palette.поверхи` ──
    # Доти суд порівнював стрибок із голим `value_gap`, а ранг уже пускав основу
    # на крок далі при помітному макіяжі (K-CLR-03): ранг радив — суд карав.
    ліміт, важіль = _KC.дозволений_контраст(особа)
    Δ_мк = float(важіль["Δ"]) if важіль else 0.0
    # Ланцюг не потребує площі, але потребує відомого боку місця кожної можливої поверхні:
    # невідомий проміжний колір міг би змінити найбільший стрибок усього ланцюга.
    поверхні = [e for e in E if частка_понад(e, 0.02) != "ні" and not _метал_зі_слова(e)]
    невідомі = [e for e in поверхні if _МІСЦЕ.бік_межі(e) is None]
    if невідомі:
        return [брак("K-CLR-02", невідомі, ("місце_речі",), "місце речі біля обличчя невідоме")]
    nf = [e for e in поверхні if _МІСЦЕ.бік_межі(e) is True]
    if not nf: return []
    буфер = any(e.get("виріз") == "відкритий" for e in nf)

    def _стрибок(Ls):
        """(ланцюг, gap, a, b, еф, Δ, Δ_власний, клас) для світлот `Ls` речей `nf` (по порядку)."""
        ланцюг = sorted([dict(хто="шкіра обличчя", L=особа["L_шкіри"])] +
                        [dict(хто=e["річ"], L=L) for e, L in zip(nf, Ls)], key=lambda d: d["L"])
        розриви = [(ланцюг[i+1]["L"] - ланцюг[i]["L"], ланцюг[i]["хто"], ланцюг[i+1]["хто"])
                   for i in range(len(ланцюг)-1)]
        gap, a, b = max(розриви, key=lambda t: t[0])
        еф = gap - (C["buffer"] if буфер else 0)
        Δ = еф - ліміт                    # перевищення — від ліміту з важелем (стеля)
        Δ_власний = еф - особа["value_gap"]   # недобір — від власного контрасту (дно)
        клас = "в межах"
        if Δ > C["over"]:
            L_з = lambda x: next(d["L"] for d in ланцюг if d["хто"] == x)
            L_в = L_з(max([x for x in (a, b) if x != "шкіра обличчя"], key=lambda x: abs(L_з(x) - особа["L_шкіри"])))
            клас = ("світле біля глибокої" if _KC.світле_біля_глибокої(особа.get("смуга_шкіри"), особа["L_шкіри"], L_в)
                    else "вище")
        elif Δ_власний < -C["under"]:
            клас = "нижче"
        return ланцюг, gap, a, b, еф, Δ, Δ_власний, клас

    # ── ВІКНО СЛОВА — СМУГА СВІТЛОТИ, А НЕ ТОЧКА ──
    # Доти ланцюг стояв на `e["L"]`, а в речі з кольором зі слова це був центр вікна: «бежевий» біля
    # обличчя мав одну світлоту, хоч вікно слова тягнеться на десятки L*. Тепер L* такого елемента
    # нема (`outfit.елементи`), і стрибок рахується в кожному варіанті сітки світлот вікон
    # (`колір_річ.світлоти_меж`). Вердикт стоїть, коли він однаковий у всіх варіантах, і числа знахідки —
    # з варіанта, найближчого до порога (сила — нижня межа); розійшлись — «без входу» з полем.
    import itertools as _іт, math as _м
    сітки = [світлоти_меж(e) for e in nf]
    if any(с is None for с in сітки):
        return [без_входу_кольору("K-CLR-02", [(e,) for e, с in zip(nf, сітки) if с is None],
                                  перевірка="cannot_tell_face_contrast_matches_hers")]
    # багато вікон біля обличчя — сітка рідшає (5 → 3 → 2 точки: межі й середина, далі лише межі),
    # щоб перебір лишався в межах 4096 варіантів
    while _м.prod(map(len, сітки)) > 4096 and any(len(с) > 2 for с in сітки):
        сітки = [с if len(с) <= 2 else с[::2] for с in сітки]
    варіанти = []
    for Ls in _іт.product(*сітки):
        в = _стрибок(Ls)
        # Два різні класи вже довели невизначеність; решта сітки висновку не змінить.
        if варіанти and в[-1] != варіанти[0][-1]:
            return [без_входу_кольору("K-CLR-02", [(e,) for e in nf if не_вимір(e)],
                                      перевірка="cannot_tell_face_contrast_matches_hers")]
        варіанти.append(в)
    ланцюг, gap, a, b, еф, Δ, Δ_власний, _ = (min(варіанти, key=lambda в: в[5]) if варіанти[0][-1] != "нижче"
                                              else max(варіанти, key=lambda в: в[6]))
    # R-PC-10: стрибок — РІЗНИЦЯ двох зон, тож похибки зон складаються квадратурою
    # (незалежний регіональний шум), а спільний зсув експозиції/ББ — 0 %. Доти
    # бралось max(se речей, se особи): на hex-вводі (обидва None) — те саме None.
    пох = cs.похибка_контрасту(розкид(*nf), особа.get("розкид"))
    спільне = dict(ланцюг=[(d["хто"], d["L"]) for d in ланцюг],
                   найбільший_розрив=round(gap,1), буфер_вирізу=буфер,
                   ефективний=round(еф,1), контраст_особи=особа["value_gap"],
                   ліміт_біля_обличчя=round(ліміт, 1), важіль_макіяжу=важіль)
    if Δ > C["over"]:
        сила, note = _сила("strong", Δ, C["over"], пох)
        # Правило лишає вимір і причину. Кандидатів та пропозицію з повним судом
        # будує `пропозиція_заміни`, коли добір має речі в межах запиту.
        сторони = [x for x in (a, b) if x != "шкіра обличчя"]
        L_винної = max((d["L"] for d in ланцюг if d["хто"] in сторони),
                       key=lambda L: abs(L - особа["L_шкіри"]))
        if _KC.світле_біля_глибокої(особа.get("смуга_шкіри"), особа["L_шкіри"], L_винної):
            # ГЛИБОКА ШКІРА + СВІТЛІША РІЧ (аудит/ПРОДУКТ.md п.18):
            # світле й чисте біля темного обличчя — підказка без ремонту й запиту в каталог.
            # Вимір, поріг і числа ті самі; міняється сила й те, що знахідка не просить замін.
            # Доти (`проби/temna_shkira_biloe_н6.py`): шкіра L*35 — «вище:soft» з ремонтом
            # усім 947 світлим верхам каталогу.
            _з = _зн("K-CLR-02", "hint", "світла річ біля глибокої шкіри — контраст вищий за власний, "
                        "але це доречний контраст (Flusser; Batres & Russell 2026), не вада",
                [x for x in (a, b) if x != "шкіра обличчя"],
                f"стрибок {a}→{b} = ΔL*{gap:.0f}; особа несе {особа['value_gap']:.0f}; "
                f"шкіра глибока (ITA «{особа.get('смуга_шкіри')}»), річ світліша за неї",
                заяви=[_ВМ.заява("light_item_near_deep_skin", jump=round(gap),
                                 own=round(особа["value_gap"]))],
                ламається="корпус записує гілку «вище» суперечною Batres & Russell 2026; "
                          "межа глибокої шкіри — смуги ITA, не калібрована на одязі",
                поріг=C["over"], вимір=Δ, розкид=пох) | спільне
            return [гейт_контрасту(_задум_мисматчу(_з, мисматч, особа["L_шкіри"], Δ_мк,
                                                    лише_задум=True)
                                    if мисматч else _з, особа)]
        _з = _зн("K-CLR-02", сила, "контраст біля обличчя вище за власний контраст особи — "
                    "«одяг носить людину», обличчя стирається",
            [x for x in (a, b) if x != "шкіра обличчя"],
            учасники=dict(речі=[x for x in (a, b) if x != "шкіра обличчя"], зони=["обличчя"]),
            чому=f"стрибок {a}→{b} = ΔL*{gap:.0f}" + (f" (з буфером вирізу {еф:.0f})" if буфер else "") +
            f"; особа несе всього {особа['value_gap']:.0f}" +
            (f" (+{Δ_мк:.0f} від помітного макіяжу, K-CLR-03 — і цього не вистачило)" if важіль else ""),
            заяви=[_ВМ.заява("face_contrast_above_her_own", jump=round(gap), own=round(особа["value_gap"]),
                             **({"with_neckline_buffer": round(еф)} if буфер else {}),
                             **({"makeup_plus": round(Δ_мк)} if важіль else {}))],
            ламається="високий colour contrast особи (руде волосся, яскраві очі) частково "
                      "компенсує value-стрибок; на uncontrolled-фото ця вісь недоступна — "
                      "тому правило тут свідомо консервативне",
            поріг=C["over"], вимір=Δ, розкид=пох,
            примітка=note or None) | спільне
        return [гейт_контрасту(_задум_мисматчу(_з, мисматч, особа["L_шкіри"], Δ_мк)
                                if мисматч else _з, особа)]
    if Δ_власний < -C["under"]:
        # Стеля вимоги: особі з контрастом 70+ жоден образ не відтворить стрибок біля
        # обличчя, крім чорно-білого. Корпус це й каже: для висококонтрастних м'яка
        # тональність — лише слабкий штраф. Без стелі правило вимагало б вікна [0,26]
        # і [100,100] — тобто «тільки чорне або тільки біле» (побачено на прогоні).
        # Недобір — від ВЛАСНОГО контрасту: важіль макіяжу дна не піднімає (K-CLR-03 —
        # буфер, не обовʼязок), інакше мʼякий образ із яскравою помадою карався б за крок,
        # який ця помада вже несе.
        Δ = Δ_власний
        сила, note = _сила("soft", -Δ, C["under"], пох)
        if особа["value_gap"] >= 45:
            сила, note = "hint", ("особа висококонтрастна — вимагати такого ж стрибка від "
                                  "одягу означало б дозволити лише чорно-біле; порушення слабке")
        _з = _зн("K-CLR-02", сила, "контраст біля обличчя нижчий за власний — легка вицвілість",
            [e["річ"] for e in nf],
            учасники=dict(речі=[e["річ"] for e in nf], зони=["обличчя"]),
            чому=f"найбільший стрибок {еф:.0f} проти {особа['value_gap']:.0f} у самої особи",
            заяви=[_ВМ.заява("face_contrast_below_her_own", jump=round(еф), own=round(особа["value_gap"]))],
            ламається="порушення несиметричне: недоконтраст м'якший за переконтраст — "
                      "це не привід замінювати вдалу річ",
            # обидві гілки K-CLR-02 гасяться однаково: недоконтраст так само стоїть на
            # похибці оцінки зон, і знахідка мусить її нести, а не лишати читача без числа
            поріг=C["under"], вимір=-Δ, розкид=пох,
            примітка=note or None) | спільне
        return [гейт_контрасту(_задум_мисматчу(_з, мисматч, особа["L_шкіри"], Δ_мк)
                                if мисматч else _з, особа)]
    return [dict(_зн(
        правило="K-CLR-02",
        сила="ok",
        речі=[e["річ"] for e in nf],
        суть=("контраст біля обличчя в межах власного контрасту особи"
              + (f" з важелем помітного макіяжу (+{Δ_мк:.0f} L*, K-CLR-03)"
                 if важіль and Δ_власний > C["over"] else "")),
        чому=""),
        **спільне)]

def максимум0(x):
    """x, якщо x > 0, інакше 0."""
    return x if x > 0 else 0

def реальне_вікно(w, дно=8, ширина=5):
    """Вікно, у якому реально існують речі. [2,5] — не запит у каталог, а артефакт формули."""
    return w if (w[0] >= дно and w[1] - w[0] >= ширина) else None
