def цільове_вікно(L_шкіри, gap_особи, темніша=True, важіль=0.0):
    """Вікно L*, у якому річ біля обличчя дає стрибок у межах контрасту особи.
    Це і є фільтр у каталог: не «візьміть щось світліше», а числовий діапазон.
    Двобічне: річ може бути темнішою або світлішою за обличчя — обидві гілки легітимні.
    `важіль` — крок K-CLR-03 від помітного макіяжу (`face_contrast.дозволений_контраст`):
    він розсуває лише ДАЛЬНІЙ край (стелю), ближній край від власного контрасту
    не рухається — ширина вікна росте рівно на важіль."""
    lo_gap = максимум0(gap_особи - C["under"]); hi_gap = gap_особи + float(важіль or 0.0) + C["over"]
    if темніша:
        return [round(max(0, L_шкіри - hi_gap)), round(max(0, L_шкіри - lo_gap))]
    return [round(min(100, L_шкіри + lo_gap)), round(min(100, L_шкіри + hi_gap))]

def _з_площею(E, поріг):
    """Елементи, чия площа ВИМІРЯНА і досягає порога — єдина форма участі у
    площозалежному рішенні (політика вгорі секції). Невиміряна площа не стає нулем
    і не стає «достатньою»: елемент просто не входить."""
    return [e for e in E if e.get("площа") is not None and e["площа"] >= поріг]


def _без_площі(E):
    """Елементи, яких площозалежне рішення не порахувало. Їх називають у знахідці —
    у цьому вся різниця між утриманням і мовчанням."""
    return [e for e in E if e.get("площа") is None]


def _розкид(*елементи):
    """Найгірший розкид серед зон, що беруть участь у рішенні. None, якщо жодна
    з них розкиду не несе (геометричний шлях, синтетика, ручний ввід)."""
    r = [e.get("розкид") for e in елементи if isinstance(e, dict) and e.get("розкид")]
    return max(r) if r else None

def _гейт_контрасту(зн, особа):
    """R-PC-10: вісь контрасту утримана гейтом (регіональний шум профілю з фото
    `se_L` перевищує те, що вісь розрізняє) — сила K-CLR-02 сходить на крок від
    ВЖЕ ЗРІЗАНОЇ (стеля тіру T3 = soft ставиться в `_зн`, тож крок до емісії був би
    невидимий), вага ріжеться до стелі нової категорії тим самим `обмежити_вагу`, що
    й у гейті наміру; знахідка лишається з числом. Без виміру шуму (hex-ввід) — без
    змін: сила не зростає."""
    К = особа.get("надійність_контрасту") or {}
    if (К.get("регіональний_шум") is None or К.get("надійність", 1.0) >= MIN_TO_EMIT
            or зн.get("сила") not in ПОРЯДОК):
        return зн
    i = min(ПОРЯДОК.index(зн["сила"]) + 1, len(ПОРЯДОК) - 1)
    зн = dict(зн, сила=ПОРЯДОК[i],
              примітка=((зн.get("примітка") + "; ") if зн.get("примітка") else "")
                       + f"вісь контрасту утримана гейтом ({К['чому']}) — знижено на крок")
    return обмежити_вагу([зн])[0]

def біля_обличчя(E, особа):
    """K-CLR-02 + K-CLR-03. Порівнюється НЕ загальний контраст образу, а стрибок
    світлоти у зоні обличчя — з контрастом, який особа несе сама.
    Механіка ремонту: рахується МАКСИМАЛЬНИЙ СУСІДНІЙ розрив у ланцюжку
    {шкіра} ∪ {речі біля обличчя}, а не повний розмах. Тому шарф проміжної світлоти
    справді лікує: він розбиває один стрибок на два менші. Це не окремий бонус —
    це той самий вимір."""
    if not особа.get("доступно"): return []
    # ── ТОЙ САМИЙ ЛІМІТ, ЩО В РАНЗІ ОСНОВ І У ВІКНІ `palette.поверхи` (19.09.2026) ──
    # Доти суд порівнював стрибок із голим `value_gap`, а ранг уже пускав основу
    # на крок далі при помітному макіяжі (K-CLR-03): ранг радив — суд карав.
    import face_contrast as _KC
    ліміт, важіль = _KC.дозволений_контраст(особа)
    Δ_мк = float(важіль["Δ"]) if важіль else 0.0
    # ланцюжок біля обличчя не потребує площі — лише приобличчевої ваги,
    # тому це правило працює і без виміру площ (дрібні елементи відсіюються, коли вимір є)
    # Поріг 0.5 був успадкований від таблиці слотів (верх .90). Коли near став
    # виміряним, гольф дав 0.468 і випадав із правила — тобто найважливіша річ
    # для зони обличчя мовчки не перевірялась. Тепер near — частка приобличчевого
    # ПОЛЯ, і поріг лише відсікає речі, яких біля обличчя майже нема.
    nf = [e for e in E if e["near"] >= NEAR_МІН and (e["площа"] is None or e["площа"] >= 0.02)]
    if not nf: return []
    ланцюг = sorted([dict(хто="шкіра обличчя", L=особа["L_шкіри"])] +
                    [dict(хто=e["річ"], L=e["L"]) for e in nf], key=lambda d: d["L"])
    розриви = [(ланцюг[i+1]["L"] - ланцюг[i]["L"], ланцюг[i]["хто"], ланцюг[i+1]["хто"])
               for i in range(len(ланцюг)-1)]
    gap, a, b = max(розриви, key=lambda t: t[0])
    буфер = any(e.get("виріз") == "відкритий" for e in nf)
    еф = gap - (C["buffer"] if буфер else 0)
    Δ = еф - ліміт                    # перевищення — від ліміту з важелем (стеля)
    Δ_власний = еф - особа["value_gap"]   # недобір — від власного контрасту (дно)
    # R-PC-10: стрибок — РІЗНИЦЯ двох зон, тож похибки зон складаються квадратурою
    # (незалежний регіональний шум), а спільний зсув експозиції/ББ — 0 %. Доти
    # бралось max(se речей, se особи): на hex-вводі (обидва None) — те саме None.
    пох = cs.похибка_контрасту(_розкид(*nf), особа.get("розкид"))
    спільне = dict(ланцюг=[(d["хто"], d["L"]) for d in ланцюг],
                   найбільший_розрив=round(gap,1), буфер_вирізу=буфер,
                   ефективний=round(еф,1), контраст_особи=особа["value_gap"],
                   ліміт_біля_обличчя=round(ліміт, 1), важіль_макіяжу=важіль)
    if Δ > C["over"]:
        сила, note = _сила("strong", Δ, C["over"], пох)
        # винна — та зі сторін розриву, що не є обличчям; якщо обидві речі, то дальша від шкіри
        сторони = [x for x in (a, b) if x != "шкіра обличчя"]
        винна = max(сторони, key=lambda x: abs(next(d["L"] for d in ланцюг if d["хто"]==x)
                                               - особа["L_шкіри"]))
        L_винної = next(d["L"] for d in ланцюг if d["хто"] == винна)
        вікно = цільове_вікно(особа["L_шкіри"], особа["value_gap"], темніша=L_винної < особа["L_шкіри"],
                              важіль=Δ_мк)
        return [_гейт_контрасту(_зн("K-CLR-02", сила, "контраст біля обличчя вище за власний контраст особи — "
                    "«одяг носить людину», обличчя стирається",
            [x for x in (a, b) if x != "шкіра обличчя"],
            f"стрибок {a}→{b} = ΔL*{gap:.0f}" + (f" (з буфером вирізу {еф:.0f})" if буфер else "") +
            f"; особа несе всього {особа['value_gap']:.0f}" +
            (f" (+{Δ_мк:.0f} від помітного макіяжу, K-CLR-03 — і цього не вистачило)" if важіль else ""),
            ремонт=[f"замінити «{винна}» на річ у вікні L*{вікно[0]}–{вікно[1]}",
                    "АБО відкритий виріз (шкіра як буфер, −8 L*)" if not буфер else
                    "АБО шарф/комір проміжної світлоти — розбиває стрибок на два",
                    "АБО перенести темну річ у низ: низ і взуття майже вільні (правило зони обличчя)"],
            запит=dict(слот="верх|шарф", цільова_L=вікно, гучність="C*<40",
                       чому="привести стрибок біля обличчя до контрасту особи"),
            ламається="високий colour contrast особи (руде волосся, яскраві очі) частково "
                      "компенсує value-стрибок; на uncontrolled-фото ця вісь недоступна — "
                      "тому правило тут свідомо консервативне",
            поріг=C["over"], вимір=Δ, розкид=пох,
            примітка=note or None) | спільне, особа)]
    if Δ_власний < -C["under"]:
        # Стеля вимоги: особі з контрастом 70+ жоден образ не відтворить стрибок біля
        # обличчя, крім чорно-білого. Корпус це й каже: для висококонтрастних м'яка
        # тональність — лише слабкий штраф. Без стелі правило вимагало б вікна [0,26]
        # і [100,100] — тобто «тільки чорне або тільки біле» (побачено на прогоні).
        # Недобір — від ВЛАСНОГО контрасту: важіль макіяжу дна не піднімає (K-CLR-03 —
        # буфер, не обовʼязок), інакше мʼякий образ із яскравою помадою карався б за крок,
        # який ця помада вже несе.
        Δ = Δ_власний
        сила, note = _сила("soft", -Δ, C["under"], пох)
        if особа["value_gap"] >= 45:
            сила, note = "hint", ("особа висококонтрастна — вимагати такого ж стрибка від "
                                  "одягу означало б дозволити лише чорно-біле; порушення слабке")
        return [_гейт_контрасту(_зн("K-CLR-02", сила, "контраст біля обличчя нижчий за власний — легка вицвілість",
            [e["річ"] for e in nf],
            f"найбільший стрибок {еф:.0f} проти {особа['value_gap']:.0f} у самої особи",
            ремонт=["канонічний ремонт — аксесуарний, не заміна речей: прикраса з блиском, "
                    "світла деталь біля обличчя, помада (+1 крок), принт із потрібним розкидом"],

            запит={k: v for k, v in dict(слот="шарф|прикраси",
                   цільова_L_темніше=реальне_вікно(
                       цільове_вікно(особа["L_шкіри"], особа["value_gap"], True, важіль=Δ_мк)),
                   цільова_L_світліше=реальне_вікно(
                       цільове_вікно(особа["L_шкіри"], особа["value_gap"], False, важіль=Δ_мк)),
                   # ЗВ'ЯЗОК З МЕТАЛОМ (був названий діркою, тепер машиночитний): срібло/сталь
                   # відбивають широкосмугово, тому біля обличчя піднімають СВІТЛОТУ майже без
                   # зсуву тону — інструмент саме ЦІЄЇ осі, а не температурної. Полірований
                   # фініш підсилює, оксидований майже прибирає.
                   метал=["срібло", "біле_золото", "платина", "сталь"],
                   блиск=2, полірування="полірований",
                   чому="підняти стрибок біля обличчя, не змінюючи вдалі речі; "
                        "полірована світла прикраса — прямий інструмент цієї осі").items() if v},
            ламається="порушення несиметричне: недоконтраст м'якший за переконтраст — "
                      "це не привід замінювати вдалу річ",
            # обидві гілки K-CLR-02 гасяться однаково: недоконтраст так само стоїть на
            # похибці оцінки зон, і знахідка мусить її нести, а не лишати читача без числа
            поріг=C["under"], вимір=-Δ, розкид=пох,
            примітка=note or None) | спільне, особа)]
    return [dict(правило="K-CLR-02", сила="ok",
                 суть=("контраст біля обличчя в межах власного контрасту особи"
                       + (f" з важелем помітного макіяжу (+{Δ_мк:.0f} L*, K-CLR-03)"
                          if важіль and Δ_власний > C["over"] else "")), **спільне)]

def максимум0(x): return x if x > 0 else 0

def реальне_вікно(w, дно=8, ширина=5):
    """Вікно, у якому реально існують речі. [2,5] — не запит у каталог, а артефакт формули."""
    return w if (w[0] >= дно and w[1] - w[0] >= ширина) else None
