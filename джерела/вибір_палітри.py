# ── ЇЇ ВХІД: ТЕ, ЩО ОБРАЛА ВОНА, І НІЧОГО ВІД СТИЛІСТКИ ────────────────────────
def _її(d):
    """Вхід показу → (вхід із застосованим паспортом, що обрала вона).

    Паспорт застосовується тим самим швом, що в `запити` (`_застосувати_паспорт`): намір, сцена з
    плитками й її закріплена річ з фото. Річ, яку вона принесла, стає основою до будь-якої поради
    (`річ_з_фото.основа_з_речі`) — це її дія, тож і тут основа тоді «її», а не стилістки.
    `вк` — її `вибір_кольору` рівно таким, як його надіслав показ (без основи з речі: ту міст
    щоразу рахує сам); до нього суддя дописує лише частини стилістки."""
    from міст_вхід import _застосувати_паспорт, _нормалізувати_вхід
    вк = dict((d or {}).get("вибір_кольору") or {})
    d = _нормалізувати_вхід(_застосувати_паспорт(dict(d or {})))
    база = dict(d.get("вибір_кольору") or {})
    схема = str(d.get("схема") or "").strip() or None
    return d, dict(схема=схема, гілка=(None if d.get("гілка") is None else int(d["гілка"])),
                   база=(база if база.get("база_hex") else None),
                   гама=(вк.get("насиченість") or None), вк=вк)


def _смуга_бази(база):
    """Смуга хроми основи, коли основа — клітинка ґратки (4-й сегмент ключа); інакше None
    (нейтраль і річ з фото смуги не несуть: гаму тоді обирає стилістка)."""
    ч = str((база or {}).get("база") or "").split("·")
    if (база or {}).get("база_тип") != "колір" or len(ч) != 4 or ч[3] not in _ГАМА_КОД:
        return None
    return ч[3]


_ПАМ_ЯТЬ = {}


def _ключ(d, слова=""):
    """Ключ пам'яті переліку: усе, від чого перелік залежить, — профіль, намір, сцена, її вибір, а
    також паспорт і її сирі слова (з них складено `випадок` промпта: без них у ключі новий паспорт
    дістав би стару нагоду)."""
    поля = ("шкіра", "волосся", "очі", "очі_кільце", "зріст", "обхвати", "намір", "сценарій",
            "самозвіт", "драп", "схема", "гілка", "вибір_кольору", "якір", "паспорт", "випадок")
    return _json.dumps(dict({к: d.get(к) for к in поля}, _слова=слова or ""),
                       ensure_ascii=False, sort_keys=True, default=str)


def перелік(вхід):
    """Дозволений перелік коду для ЦІЄЇ людини — схеми й основи з рангами — і її вже обране.

    Те саме, з чого вона обирає на екрані «Палітра»: розвилка з усіма шістьма гілками
    (`явні=ПОЗА_ЩОДЕННИМ`, як `міст_основи.палітри`) і ряд рекомендованих основ (`_основи`, K-CLR-02
    уже відсік усе нижче підлоги). Порядок — ранг коду: схеми — порядок розвилки, основи — бал.
    Нейтральна клітинка ґратки однакова в усіх трьох смугах хроми (той самий hex), тож іде одним
    записом зі смугою «any». Пам'ять на ключ входу — щоб крок 2 судив рівно тим переліком, який
    бачила модель, і не рахував його вдруге."""
    d, її = _її(вхід)
    к = _ключ(d, (вхід or {}).get("вимоги"))
    if к in _ПАМ_ЯТЬ:
        return _ПАМ_ЯТЬ[к]
    import palette as _П
    import міст_основи as _МО
    from міст_вхід import _збірка, _якір, _самозвіт
    намір = d.get("намір") or "conventional"
    F, T, зріст, kw = _збірка(d)
    п = _МО._пакет(F, T, зріст, kw, _якір(d), намір, _самозвіт(d), d.get("вибір_кольору"),
                   d.get("драп"), явні=_П.ПОЗА_ЩОДЕННИМ)
    if not п.get("готово"):
        return dict(помилка=п.get("чому") or "пакет палітри не зібрався")
    схеми = []
    for і, г in enumerate(п["палітри"]["розвилка"]):
        ноти = [з for з in ((г.get("нота_кодами") or {}).get("statements") or [])
                if not (str(з.get("code")).startswith("scheme_") or з.get("code") == "contrast_mismatch")]
        схеми.append(dict(схема=г["схема"], код=_ДМ._СХЕМА.get(г["схема"], г["схема"]), ранг=і + 1,
                          вага=_ВАГА.get(г.get("вага"), г.get("вага")),
                          надійність=г.get("надійність_ранг"), радить=not г.get("поза_порадою"),
                          ноти=ноти))
    рек = sorted(enumerate((п.get("основи_кольорів") or {}).get("рекомендовані") or []),
                 key=lambda x: (-(x[1].get("бал") or 0.0), x[0]))
    основи, бачені = [], set()
    for _, о in рек:
        ч = str(о.get("ключ") or "").split("·")
        if len(ч) != 4:
            continue
        ахром = ч[1] == "нейтраль"
        if ахром and (ч[0], ч[2]) in бачені:
            continue
        if її["гама"] and not ахром and ч[3] != її["гама"]:
            continue                    # гаму вона обрала сама: колір основи — лише з її смуги
        бачені.add((ч[0], ч[2]))
        основи.append(dict(id="b%d" % (len(основи) + 1), ключ=о["ключ"], назва=о.get("назва") or ч[0],
                           hex=о.get("hex"), ахром=ахром, смуга=(None if ахром else ч[3]),
                           L=int(ч[2]), сім_я=о.get("сім_я"), темп=ч[1], бал=о.get("бал")))
    for і, о in enumerate(основи):
        о["ранг"] = і + 1
        о["очі"] = _до_очей(о, F)
    пер = dict(схеми=схеми, основи=основи, її=її, особа=_особа(F, п), намір=намір,
               випадок=_випадок(d, (вхід or {}).get("вимоги")), помилка=None)
    if len(_ПАМ_ЯТЬ) >= 4:
        _ПАМ_ЯТЬ.clear()
    _ПАМ_ЯТЬ[к] = пер
    return пер


def _сім_я(h, C):
    """Сім'я тону риси кодом (`palettes.сім_я_тону` → `дріт_моделі._СІМ_Я`), «neutral» — нижче межі тону."""
    import palettes as _ПЛ
    if h is None or C is None or float(C) < _ТОН_РИСИ_С_МІН:
        return "neutral"
    с = _ПЛ.сім_я_тону(float(h) % 360)
    return _ДМ._СІМ_Я.get(с[0], с[0]) if с else "unknown"


def _особа(F, п):
    """Її колорит кодами й числами: контраст і щілина, підтон (той самий клас і джерело, що бачить
    рука 1 — `пакет_моделі.людина_для_пакета`), очі, волосся, шкіра, бік очей на осі b*, метал."""
    import palette as _П
    import пакет_моделі as _ПМ
    л = _ПМ.людина_для_пакета(None, п.get("палітри"))
    о = {"contrast": {"level": _ДМ._КОНТРАСТ.get(п["особа"].get("рівень"), _ВМ.UNKNOWN),
                      "light_dark_gap": round(float(п["особа"].get("value_gap") or 0), 1)},
         "undertone": {"class": _ДМ._ТЕМПЕРАТУРА.get(л["температура"]["клас"], л["температура"]["клас"]),
                       "from": _ДМ._ДЖЕРЕЛО_ТЕМПЕРАТУРИ.get(л["температура"]["джерело"])}}
    for риса, ключ in (("очі", "eyes"), ("волосся", "hair"), ("шкіра", "skin")):
        р = F.get(риса) or {}
        if р.get("L") is None:
            continue
        о[ключ] = {"family": _сім_я(р.get("h"), р.get("C")), "lightness": round(float(р["L"])),
                   "chroma": round(float(р.get("C") or 0))}
    б = _П.бік_b_проти_людини(F)
    if "eyes" in о:
        о["eyes"]["yellow_blue"] = ("yellow" if б.get("бік", 0) > 0 else "blue" if б.get("бік", 0) < 0
                                    else "none")
    метал = (п.get("основи_кольорів") or {}).get("метал")
    if метал:
        о["metal"] = _ДМ._МЕТАЛ.get(метал, метал)
    # ЯСНІСТЬ І СВІТЛОТА — ФАКТОМ, А НЕ ЗДОГАДОМ (рядки 1400–1401, 02.10.2026). Гаму при
    # нейтральній основі обирає стилістка, а про ясність людини вона бачила лише C* рис —
    # і C*3 чорного волосся читала як «приглушена»: ПІСЛЯ правки рангу (кольорові основи
    # рангів 1–2 «середні/насичені») ж3 і ж8 брали графіт і ставили «muted» у 3 з 3
    # прогонів. Тепер їде та сама вісь, якою код будує палітру (`palettes.осі`: волосся без
    # тону голосує лише світлотою), і ознака «обидва кінці світлоти» за високого контрасту.
    import palettes as _ПЛ
    ос = _ПЛ.осі(F)
    о["axes"] = {"lightness": ос["коди"]["value"], "clarity": ос["коди"]["chroma"]}
    if ос.get("обидва_полюси_L"):
        о["axes"]["both_lightness_ends"] = True
    return о


