# ЧАСТИНИ ВИБОРУ Й ХТО ЇХ ОБРАВ — КОДАМИ (рядок 205, 28.09.2026, CLAUDE.md п.12).
# `лишила`, ключі `обрала`/`причини` і їхні значення їдуть рядком діагнозу
# `palette · choice · …` у звіт власника і полем `палітра.обрала` у вердикт, тобто
# читає їх код і читає власник, а не жінка: кириличні слова тут були словником коду,
# який ламався б від локалізації. Речення жінці, як і доти, пише мовна модель із
# `повідомлення` нижче — там коди заяв, не ці.
ЧАСТИНИ = ("scheme", "base", "saturation")
ХТО_ВОНА, ХТО_СТИЛІСТКА, ХТО_КОД = "her", "stylist", "code_rank"


def що_лишила(пер):
    """Які частини вона лишила стилістці: підмножина `ЧАСТИНИ` (`scheme`, `base`, `saturation`)."""
    її = пер["її"]
    лишила = []
    if not її["схема"] and її["гілка"] is None:
        лишила.append("scheme")
    if not її["база"]:
        лишила.append("base")
    if not її["гама"] and not _смуга_бази(її["база"]):
        лишила.append("saturation")
    return лишила


def дані_промпта(пер):
    """Перелік → дані входу оголошення `ВИБІР` (коди й числа)."""
    її, fixed = пер["її"], {}
    if її["схема"] or її["гілка"] is not None:
        г = next((с for с in пер["схеми"] if с["схема"] == її["схема"]), None) or \
            (пер["схеми"][її["гілка"]] if її["гілка"] is not None and її["гілка"] < len(пер["схеми"]) else None)
        if г:
            fixed["scheme"] = г["код"]
    if її["база"]:
        fixed["base"] = _її_основа_дротом(її["база"])
    if її["гама"]:
        fixed["saturation"] = _ГАМА_КОД.get(її["гама"], її["гама"])
    return dict(person=пер["особа"], occasion=пер["випадок"],
                schemes=[dict({"rank": с["ранг"], "scheme": с["код"], "weight": с["вага"],
                               "advised": с["радить"]},
                              **({"reliability": с["надійність"]} if с["надійність"] else {}),
                              **({"notes": с["ноти"]} if с["ноти"] else {})) for с in пер["схеми"]],
                bases=[_основа_дротом(о) for о in пер["основи"]],
                fixed=fixed, reason_codes=dict(ПРИЧИНИ))


# ── КРОК 2: СУДДЯ ──────────────────────────────────────────────────────────
def _причини(сирі, куди):
    """Коди причин моделі → лише з `ПРИЧИНИ`, без повторів, не більше `_ПРИЧИН_МАКС`; чужі — у `куди`."""
    вих = []
    for к in (сирі if isinstance(сирі, list) else []):
        к = str(к).strip()
        if к in ПРИЧИНИ and к not in вих:
            вих.append(к)
        elif к:
            # рядок 205: `відхилено` їде рядком діагнозу `palette · choice · rejected=` — кодом
            куди.append("reason_outside_list:%s · taken=none" % к)
    return вих[:_ПРИЧИН_МАКС]


def _відтінок(L):
    """Світлота клітинки → код відтінку для заяви: light / dark / None (та сама межа, що на чипі)."""
    return "light" if L >= 68 else ("dark" if L <= 32 else None)


def прийняти(вхід, відповідь=None, без_моделі=None):
    """Крок 2: відповідь моделі (або її брак) → вибір, який можна нести в пул, із вироком судді.

    Кожна частина (схема, основа, гама) судиться окремо: те, що обрала вона, — її; те, що модель
    назвала з переліку, — стилістки; решта — ранг коду з причиною (`обрала="код"`): схема — перша
    гілка розвилки, основа — не обрана (дуги схеми стають від її рис, як доти), гама — «середні».
    `вибір.схема` / `вибір.вибір_кольору` — рівно те, що показ кладе в `запити` і `від_моделі`."""
    пер = перелік(вхід)
    if пер.get("помилка"):
        return dict(помилка=пер["помилка"])
    її, лишила = пер["її"], що_лишила(пер)
    відхилено, знахідки = [], []
    # ЧОМУ СТИЛІСТКА НЕ ОБРАЛА — КОДОМ (для заяви) І СЛОВАМИ (для звіту): моделі не питали чи
    # вона не відповіла (`без_моделі` від показу) — «no_model»; відповідь не прочиталась — «unreadable».
    чому_код = "no_model" if без_моделі is not None else None
    об = None
    if без_моделі is None:
        об, чому_не, _ = _ПР.розбір_останній(str(відповідь or ""), ("scheme",))
        if not isinstance(об, dict):
            без_моделі, чому_код = ("відповідь моделі не прочиталась (%s)" % (чому_не or "не JSON-обʼєкт"),
                                    "unreadable")
    об = об if isinstance(об, dict) else {}
    обрала, причини = {}, {}
    # ── СХЕМА ──
    г = None
    if "scheme" not in лишила:
        г = next((с for с in пер["схеми"] if с["схема"] == її["схема"]), None) or \
            (пер["схеми"][min(її["гілка"], len(пер["схеми"]) - 1)] if її["гілка"] is not None else None)
        обрала["scheme"] = ХТО_ВОНА
    elif без_моделі is None:
        г = next((с for с in пер["схеми"] if с["код"] == str(об.get("scheme") or "").strip()), None)
        if г:
            обрала["scheme"], причини["scheme"] = ХТО_СТИЛІСТКА, _причини(об.get("scheme_reasons"), відхилено)
        else:
            відхилено.append("scheme_outside_list:%s · taken=first_branch" % (об.get("scheme") or "none"))
    if г is None:
        г, обрала["scheme"] = пер["схеми"][0], обрала.get("scheme") or ХТО_КОД
    # ── ОСНОВА ──
    о = None
    if "base" in лишила and без_моделі is None:
        о = next((x for x in пер["основи"] if x["id"] == str(об.get("base") or "").strip()), None)
        if о:
            обрала["base"], причини["base"] = ХТО_СТИЛІСТКА, _причини(об.get("base_reasons"), відхилено)
            if "why_her_eyes" in причини["base"] and not о.get("очі"):
                # рядок 1421: основа до очей не стоїть ні повтором, ні комплементом — причина неправдива
                причини["base"].remove("why_her_eyes")
                відхилено.append("reason_not_in_data:why_her_eyes · base_eyes=none · taken=none")
        else:
            відхилено.append("base_outside_list:%s · taken=none" % (об.get("base") or "none"))
    обрала.setdefault("base", ХТО_ВОНА if "base" not in лишила else ХТО_КОД)
    # ── ГАМА ── колір основи несе свою смугу; нейтраль лишає гаму стилістці, а без неї — «середні»
    гама = її["гама"]
    if гама:
        обрала["saturation"] = ХТО_ВОНА
    elif о is not None and not о["ахром"]:
        гама, обрала["saturation"] = о["смуга"], ХТО_СТИЛІСТКА
    elif "saturation" in лишила and без_моделі is None and ГАМИ.get(str(об.get("saturation") or "").strip()):
        гама, обрала["saturation"] = ГАМИ[str(об["saturation"]).strip()], ХТО_СТИЛІСТКА
    elif _смуга_бази(її["база"]):
        гама, обрала["saturation"] = _смуга_бази(її["база"]), ХТО_ВОНА
    else:
        гама, обрала["saturation"] = _ГАМА_БЕЗ_ВИБОРУ, ХТО_КОД
    # ── ЗНАХІДКА K-COL-03: СТИЛІСТКА ВЗЯЛА НЕ ПЕРШУ ГІЛКУ ──
    # `діагностика` — ТІ САМІ ФАКТИ КОДАМИ Й ЧИСЛАМИ (рядок 205, 28.09.2026): рядок
    # діагнозу `palette · choice · finding=…` доти переказував `суть` прозою, і звіт
    # власника ніс те саме двічі — реченням і полями `scheme_rank`/`scheme_rare` поруч.
    # `суть`/`чому` лишаються там, де їх оголосив П-6: у самій знахідці, для звіту.
    if обрала["scheme"] == ХТО_СТИЛІСТКА and г["ранг"] > 1:
        import реєстр_правил as _РЕЄСТР
        знахідки.append(_РЕЄСТР._зн(
            "K-COL-03", "hint" if г["радить"] else "soft",
            "стилістка взяла схему «%s» — ранг %d з %d%s" % (г["схема"], г["ранг"], len(пер["схеми"]),
                                                             "" if г["радить"] else ", рідший хід для цього наміру"),
            [], "ранг — порядок згоди практиків під її контраст (K-COL-03); причини стилістки: %s"
                % (", ".join(причини.get("scheme") or []) or "не названо"),
            діагностика=dict(scheme=г["код"], scheme_rank=г["ранг"], of_schemes=len(пер["схеми"]),
                             advised=bool(г["радить"]), chosen_by=ХТО_СТИЛІСТКА,
                             reasons=list(причини.get("scheme") or []))))
    вк = dict(її["вк"])
    if о is not None:
        вк.update(база=о["ключ"] if not о["ахром"] else "·".join(о["ключ"].split("·")[:3] + [гама]),
                  база_hex=о["hex"], база_тип=("нейтраль" if о["ахром"] else "колір"), база_стилістки=True)
    if обрала["saturation"] == ХТО_СТИЛІСТКА:
        вк["насиченість"] = гама
    return dict(
        вибір=dict(схема=г["схема"], ранг_схеми=г["ранг"], схема_рідша=not г["радить"],
                   вибір_кольору=(вк or None), основа_ранг=(о["ранг"] if о else None),
                   гама=гама, обрала=обрала, причини=причини),
        лишила=лишила, знахідки=знахідки, відхилено=відхилено, без_моделі=без_моделі,
        повідомлення=повідомлення(г, о, гама, обрала, причини, лишила,
                                  чому_код or ("outside_list" if відхилено else None)))


def повідомлення(г, о, гама, обрала, причини, лишила, чому_код=None):
    """Рядок на екрані «Палітра» заявами (Ч-1, п.12) про те, що вона лишила стилістці: що обрала
    стилістка й чому; чого не обрала — чесно, і за чим тоді збирається образ. Речення пише мовна
    модель; без неї рядка нема. Обране нею тут не повторюється — про це свій рядок (нота схеми)."""
    назва = str(г["схема"]).replace("_", " ")
    # «не обрала» стоїть поруч із ТІЄЮ частиною, яку взяв ранг коду (схема чи основа), а не
    # шапкою рядка: друга частина могла бути обрана, і сказати «не обрала» про весь вибір — неправда.
    # Гама без вибору — «середні», як доти; це не «стилістка не обрала», тож заяви про неї нема.
    заяви = []
    не_обрала = _ВМ.заява("stylist_did_not_choose", why=(чому_код or "no_model"))
    if "scheme" in лишила:
        if обрала.get("scheme") == ХТО_СТИЛІСТКА:
            заяви += [_ВМ.заява("stylist_chose_scheme", scheme=назва)] + \
                     [_ВМ.заява(к) for к in причини.get("scheme") or []]
        else:
            заяви += [не_обрала, _ВМ.заява("first_scheme_of_advice", scheme=назва)]
    if "base" in лишила:
        if обрала.get("base") == ХТО_СТИЛІСТКА and о is not None:
            з = dict(base=о["назва"])
            if _відтінок(о["L"]):
                з["shade"] = _відтінок(о["L"])
            заяви += [_ВМ.заява("stylist_chose_base", **з)] + \
                     [_ВМ.заява(к) for к in причини.get("base") or []]
        else:
            заяви += ([] if не_обрала in заяви else [не_обрала]) + [_ВМ.заява("base_from_her_features")]
    if "saturation" in лишила and обрала.get("saturation") == ХТО_СТИЛІСТКА and (о is None or о["ахром"]):
        заяви.append(_ВМ.заява("stylist_chose_saturation", saturation=_ГАМА_КОД.get(гама, гама)))
    if not заяви:
        return None
    вид = "palette_stylist_choice" if ХТО_СТИЛІСТКА in обрала.values() else "palette_default_scheme"
    return _ВМ.повідомлення(вид, *(заяви + [_ВМ.заява("choose_another_if_wants")]))


# ── ЯК ЦЕ ВИДНО СУДДІ ОБРАЗУ Й ЗВІТУ ────────────────────────────────────────
def для_суду(d):
    """Хто обрав схему цього прогону — для запису вердикта й пункту P8 чекліста палітри.

    `вибір_стилістки` показ кладе у вхід `запити`/`від_моделі` лише тоді, коли стилістку питали
    (прийнятий вихід `прийняти`). Нема його — питали не показом (CLI, стенд, батареї) або вона все
    обрала сама. `обрала` — dict частина (`scheme`/`base`/`saturation`) → `her` | `stylist` |
    `code_rank`; `бракує` — назване поле для «без входу», коли схему узяв ранг коду (кодом, рядок 205)."""
    вс = d.get("вибір_стилістки") if isinstance(d.get("вибір_стилістки"), dict) else None
    її_схема = bool(str(d.get("схема") or "").strip()) or d.get("гілка") is not None
    if вс:
        обрала = dict((вс.get("вибір") or {}).get("обрала") or {})
        бракує = None
        if обрала.get("scheme") == ХТО_КОД:
            бракує = "stylist_choice · %s" % (вс.get("без_моделі") or " | ".join(вс.get("відхилено") or [])
                                              or "scheme_from_code_rank")
        return dict(обрала=обрала, причини=(вс.get("вибір") or {}).get("причини") or {},
                    знахідки=вс.get("знахідки") or [], відхилено=вс.get("відхилено") or [],
                    без_моделі=вс.get("без_моделі"), бракує=бракує)
    if її_схема:
        return dict(обрала={"scheme": ХТО_ВОНА}, причини={}, знахідки=[], відхилено=[], без_моделі=None,
                    бракує=None)
    return dict(обрала={"scheme": ХТО_КОД}, причини={}, знахідки=[], відхилено=[], без_моделі=None,
                бракує="stylist_choice · not_in_input · scheme_from_code_rank:first_branch")


def лише_її(вибір_кольору, вибір_стилістки=None):
    """`вибір_кольору` без частин стилістки — для рук 3–4 (модель без коду й без каталогу): вони
    бачать лише ЇЇ явний вибір, як доти (CLAUDE.md п.1: логіка рук лишається як є). Вибір стилістки
    стоїть на переліку й рангах коду, тож у руках без коду йому не місце."""
    вк = dict(вибір_кольору or {})
    if вк.pop("база_стилістки", None):
        for к in ("база", "база_hex", "база_тип"):
            вк.pop(к, None)
    if (((вибір_стилістки or {}).get("вибір") or {}).get("обрала") or {}).get("saturation") == ХТО_СТИЛІСТКА:
        вк.pop("насиченість", None)
    return вк or None


def вибір_палітри(вхід):
    """Ендпойнт моста `вибір_палітри` (два кроки, див. шапку модуля)."""
    d = _json.loads(вхід) if isinstance(вхід, str) else (вхід or {})
