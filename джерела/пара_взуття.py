# -*- coding: utf-8 -*-
"""пара_взуття.py — факти пари взуття: каблук (є чи нема, висота, смуга, клас, вид) і підошва. ОДНЕ визначення для суду,
відбору пулу за її проханням і рядка стилістки (Річ-запис-речі п.7, наряд «один запис пари», 17.11.2026; дошка 16259,
16274, 16283, 16284).

ЩО БУЛО. Каблук і підошву пари визначали кілька місць, і кожен читач брав своє: суд ціни каблука, стеля «зручність
передусім» і підйом під максі — число запису; відбір пулу за її «без підборів» / «на підборах» (`каблук.відсів`) — лише
здогад із назви й адреси, який `міст_пакет` дописував у рядок пулу полем `каблук_є`; сенсорне вето — чотири гілки разом;
суд ожеледі — підрядок у полі `підошва`; коди картки (#4045) — лише рядок стилістки. Лічба #4141/#4151 на 3 399 парах: у
234 парах запис каже «каблук є», а назва — «нема», і прохання «на каблуку» знімало їх із пулу, а на «без каблука» лишались
1 656 пар із каблуком; суд ожеледі знав підошву 334 пар, хоч коди картки має 1 301.

ЩО СТАЛО. Запис пари (`фід_взуття.взуттєві_поля`) несе значення разом із джерелом: `каблук_джерело` і `висота_джерело`
(`ДЖЕРЕЛА`, від найсильнішого: число крамниці, смуга крамниці, слово картки, слова опису й назви). Здогад із назви й
адреси (`каблук.каблук`) — найслабше джерело того самого факту, а не окреме поле пулу: він діє, лише коли запис мовчить.
Читачі беруть факт тут і нічого не виводять самі.

«КАБЛУК Є» — ТРИ ВІДПОВІДІ З ФАКТІВ, НЕ ПОЛЕ (рішення менеджера 17.11, дошка 16293, 16294). Запис несе окремі факти
пари зі своїм джерелом: висоту каблука (число, смуга), слово крамниці про каблук (картка, опис, назва — `каблук` запису,
вид і клас картки) і платформу. Платформа — ознака підошви, не каблук: сама платформа «каблук є» не дає. «Каблук є»
виводить з них лише `каблук`:
  · «так» — крамниця назвала каблук словом (вид каблука чи клас low, mid, high) або висота не нижча за поріг, з якого
    база знань лічить ціну каблука (`каблук_смуга_низ` K-SHO-16 — той самий, що в стелі comfort_first; власного
    означення «низького ходу» база не має);
  · «ні» — «без каблука», «низький хід» (клас flat), висота нуль або тип пари, що каблука не має (`каблук.ПЛОСКІ`);
  · «не визначено» (None) — число нижче порога без слова крамниці, сама платформа, мовчання.
Відбір за її проханням і вето «не ношу підборів» знімають лише те, що суперечить напевно; «не визначено» лишається в
пулі, а факт (висота, платформа) іде в рядок стилістки — обирає вона (`аудит/ПРОДУКТ.md`, п.17). Нового порога в
сантиметрах нема: межа — константа бази знань.

Підошва — коди переліку картки (`картка_взуття.ПІДОШВА`) разом з основою слів крамниці про підошву (`підошва` запису,
`фід_взуття.підошва_картки`; джерело — `підошва_джерело`: параметр картки чи текст), перекладеною тим самим кодом. Гладка для ожеледі — ті самі два питання, що суд ставив
словами («гладк», «шкіряна підошва»), кодами: `ГЛАДКА`.

Висота платформи й підошви (`платформа_висота`, `платформа_чия`; дошка 16174) — слово крамниці для стилістки; суд її не читає (правила
про платформу в базі знань нема).
"""
import functools

import каблук as _КБ

# ── ДЖЕРЕЛА ЗНАЧЕНЬ, від найсильнішого (пише `фід_взуття.взуттєві_поля`, `картка_в_запис`) ──
ЧИСЛО, СМУГА, КАРТКА, ТЕКСТ, НАЗВА = "число", "смуга", "картка", "текст", "назва"
ДЖЕРЕЛА = (ЧИСЛО, СМУГА, КАРТКА, ТЕКСТ, НАЗВА)
# запис без поля джерела (її річ, старий кеш, рядок стенда): значення є, звідки — не записано
ЗАПИС = "запис"

# здогад із назви (`каблук.каблук`: «тонкий», «товстий»; «високий», «низький») → коди картки (`картка_взуття.ВИД`,
# `картка_взуття.РІВЕНЬ`); «товстий» картка не має — код переліку розбору `thick`
ВИД_З_НАЗВИ = {"тонкий": "thin", "товстий": "thick"}
КЛАС_З_НАЗВИ = {"високий": "high", "низький": "low"}

# основа слів картки про підошву (`фід_взуття.ПІДОШВИ`) → код переліку підошви (`каталог_розбір.ПІДОШВА`);
# «прошит» — кріплення підошви (`каталог_розбір.КРІПЛЕННЯ_ПІДОШВИ`), не матеріал
ПІДОШВА_ЗА_ОСНОВОЮ = {"поліуретан": "polyurethane", "eva": "eva", "ева": "eva", "теп": "tpr", "термоеластопласт": "tpr",
                      "тракторн": "lug", "протектор": "lug", "прошит": "stitched", "шкіряна підошва": "leather",
                      "гладк": "smooth"}
# K-WEA-06: «повністю гладка підошва — однозначне «ні» для зими» — ті самі два слова, що суд шукав у полі `підошва`
# («гладк», «шкіряна підошва»), кодами
ГЛАДКА = frozenset(("smooth", "leather"))

# вид каблука картки, що каблука не називає: платформа — ознака підошви (`платформа`), не каблук
НЕ_КАБЛУК = frozenset(("platform",))
# клас картки «без каблука», «низький хід» (`картка_взуття.ЧИТАННЯ`: каблук no, рівень flat)
КЛАС_БЕЗ = "flat"


@functools.lru_cache(maxsize=1)
def поріг():
    """Висота, з якої база знань лічить ціну каблука, см (`каблук_смуга_низ`, K-SHO-16, T2)."""
    import аксесуари_реєстр as _АР          # пізно: реєстр правил тягне суд, а запис пари пише фід
    return float(_АР.C["каблук_смуга_низ"])


@functools.lru_cache(maxsize=65536)
def _з_назви(назва, тип, url):
    return _КБ.каблук(назва, {"тип": тип} if тип else None, url)


def з_назви(р):
    """Здогад із назви, типу й адреси пари (`каблук.каблук`): dict(є, форма, висота, джерело, сила). Тип читається тим
    самим `каблук.ПЛОСКІ` / `З_КАБЛУКОМ`: «тип пари каблука не має» — та сама категорія, що в назві."""
    return _з_назви(р.get("назва"), р.get("тип"), р.get("url"))


def висота(р):
    """(см, джерело) — число висоти каблука, яке крамниця дала (поле, картка чи опис), або (None, None)."""
    h = р.get("каблук_см")
    if h is None:
        return None, None
    return float(h), р.get("висота_джерело") or ЗАПИС


def смуга(р):
    """(від, до, слова) — смуга фільтра крамниці («від 4 до 6 см»; `від`/`до` None — відкритий бік), або None."""
    від, до = р.get("каблук_від"), р.get("каблук_до")
    if від is None and до is None:
        return None
    return (None if від is None else float(від), None if до is None else float(до), р.get("каблук_клас"))


def висота_від(р):
    """Висота пари для питання «чи вона ВИЩА за поріг», см, або None: число крамниці, а без нього — НИЖНІЙ край смуги
    («більше 6 см» доводить, що пара не нижча за 6). Смуга без нижнього краю («до 4 см (або без підборів)») нічого не
    доводить — None. Для питання «чи вона НИЖЧА» не годиться: з «до 4» пара може бути і 4 см, і 0."""
    h = висота(р)[0]
    if h is not None:
        return h
    с = смуга(р)
    return None if с is None else с[0]


def каблук(р):
    """(є, джерело): True («так») / False («ні») / None («не визначено», не «нема») і звідки — одне визначення.

    Факти — від найсильнішого джерела, перший, що вирішує: число (поріг — `поріг()`; нуль — «ні»; нижче порога не
    вирішує), смуга (нижній край не нижчий за поріг — «так»; верхній нуль — «ні»), слово крамниці про каблук (`каблук`
    запису: картка, опис), вид і клас картки, назва й тип пари (`каблук.каблук`). Сама платформа нічого не вирішує."""
    h = висота(р)[0]
    if h is not None:
        if h >= поріг():
            return True, р.get("висота_джерело") or ЗАПИС
        if h == 0:
            return False, р.get("висота_джерело") or ЗАПИС
    с = смуга(р)
    if с:
        if с[0] is not None and с[0] >= поріг():
            return True, СМУГА
        if с[1] is not None and с[1] == 0:
            return False, СМУГА
    є = р.get("каблук")
    if isinstance(є, bool):
        return є, р.get("каблук_джерело") or ЗАПИС
    рівень = set(р.get("каблук_рівень") or ())
    if КЛАС_БЕЗ in рівень:
        return False, КАРТКА
    if рівень or set(р.get("каблук_вид") or ()) - НЕ_КАБЛУК:
        return True, КАРТКА
    н = з_назви(р)
    if н.get("є") is not None:
        return н["є"], НАЗВА
    return None, None


def вид(р):
    """(коди виду каблука, джерело): коди картки (`картка_взуття.ВИД`) старші за форму зі здогаду назви; ([], None)."""
    в = [к for к in р.get("каблук_вид") or () if к not in НЕ_КАБЛУК]
    if в:
        return в, КАРТКА
    if каблук(р)[1] == НАЗВА or р.get("каблук") is None:
        ф = ВИД_З_НАЗВИ.get(з_назви(р).get("форма"))
        if ф:
            return [ф], НАЗВА
    return [], None


def клас(р):
    """(коди класу висоти, джерело): коди картки (`картка_взуття.РІВЕНЬ`) старші за слово назви; ([], None)."""
    if р.get("каблук_рівень"):
        return list(р["каблук_рівень"]), КАРТКА
    if каблук(р)[1] == НАЗВА or р.get("каблук") is None:
        к = КЛАС_З_НАЗВИ.get(з_назви(р).get("висота"))
        if к:
            return [к], НАЗВА
    return [], None


def слово(р):
    """Що крамниця каже про каблук без числа: dict(heel_shape, heel_level, band) — коди виду й класу та слова смуги, з
    яких є; {} — крамниця сказала число чи нічого. Суд називає це слово, а не «висота невідома»."""
    вих = {}
    в, кл, с = вид(р)[0], клас(р)[0], смуга(р)
    if в:
        вих["heel_shape"] = в
    if кл:
        вих["heel_level"] = кл
    if с and с[2]:
        вих["band"] = с[2]
    return вих


def словами(р):
    """Рядок «без каблука» / «каблук не оголошений» / «каблук: …» (`каблук.словами`) з одного визначення — для шапки
    групи пулу й поля `каблук` рядка пулу."""
    є = каблук(р)[0]
    н = з_назви(р)
    return _КБ.словами(dict(є=є, форма=н.get("форма") if є else None, висота=н.get("висота") if є else None))


def під_межею_підборів(р):
    """Чи сенсорна межа «не ношу підборів» (K-PER-05) знімає пару: лише «так» одного визначення. «Не визначено»
    лишається в пулі — факт іде в рядок стилістки, обирає вона (рішення 17.11, п.17)."""
    return р.get("слот") == "взуття" and каблук(р)[0] is True


def підошва(р):
    """(коди підошви, джерело): коди картки (`підошва_коди`) і основа слів крамниці про підошву (`підошва`) тим самим
    переліком, без повтору; ([], None) — крамниця підошви не назвала. Джерело — КАРТКА, коли є коди картки; інакше
    те, що записав писач основи (`підошва_джерело`: КАРТКА — параметр картки, ТЕКСТ — опис чи назва; дошка 16317),
    а без поля — ЗАПИС."""
    коди = list(р.get("підошва_коди") or ())
    осн = р.get("підошва")
    if осн:
        к = ПІДОШВА_ЗА_ОСНОВОЮ.get(осн, осн)
        if к not in коди:
            коди.append(к)
    if not коди:
        return коди, None
    if р.get("підошва_коди"):
        return коди, КАРТКА
    return коди, р.get("підошва_джерело") or ЗАПИС


def підошва_гладка(р):
    """True — крамниця назвала гладку підошву (`ГЛАДКА`); False — назвала іншу; None — не назвала."""
    коди = підошва(р)[0]
    if not коди:
        return None
    return bool(ГЛАДКА & set(коди))


def слова_підошви(р):
    """Слова крамниці про підошву (основа з картки) — для жорсткого «ні» словом (`profile.вето_збіг`), або None."""
    return р.get("підошва") or None


def платформа(р):
    """Платформа пари — ознака підошви, не каблук: dict(of: platform|sole, shop: «2,5 см») — висота словом крамниці
    (дошка 16174); dict(of="platform") — картка назвала платформу без висоти; None — крамниця не назвала."""
    if р.get("платформа_висота"):
        return dict(of=р.get("платформа_чия") or "platform", shop=р["платформа_висота"])
    if НЕ_КАБЛУК & set(р.get("каблук_вид") or ()):
        return dict(of="platform")
    return None


def відсів(речі, запит):
    """(лишилось, вибуло, чому) — відбір взуття під її прохання про каблук («є» / «нема», `каблук.ПРОХАННЯ_КОДИ`;
    «тонкий», «високий» — як «є»).

    Знімається лише пара, чий каблук (одне визначення `каблук`) суперечить проханню. Пара з невідомим каблуком лишається:
    «не оголошено» — не «не підходить»."""
    if not запит:
        return list(речі), [], "прохання про взуття не було"
    лиш, геть, невідомо = [], [], 0
    for r in речі:
        є = каблук(r)[0]
        погано = (є is False) if запит in ("тонкий", "високий", "є") else (є is True)
        (геть if погано else лиш).append(r)
        невідомо += (є is None and not погано)
    чому = ("прохання «%s»: %d речей суперечать визначенням і зняті, %d лишились (з них %d без оголошеного каблука)"
            % (запит, len(геть), len(лиш), невідомо))
    return лиш, геть, чому
