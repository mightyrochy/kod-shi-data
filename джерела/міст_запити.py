def _брифи(d, п, T, гілка, пд, T_д, гд, інвертувати, вимоги=""):
    """Брифи обох плечей ОДНИМ джерелом: (бриф B, бриф C, вимкнені коди).

    ЧОМУ ЦЕ СТАЛО ФУНКЦІЄЮ (Т-02). Правила перестали бути абзацом у хвості
    промпта й стали полем `ПАКЕТ_V1.правила` — тобто вони тепер ВСЕРЕДИНІ пакета,
    довжину якого міряє бюджет (`_пакет_у_бюджет`). А пул мусить бути ТОЙ САМИЙ у
    `запити` (де складають образи) і у `від_моделі` (де їх судять): інакше номер
    «#412·29» з відповіді моделі резолвиться в ІНШУ річ іншого магазину — рівно
    той дефект, який 02.09 ловили на нумерації вітрини. Отже обидва ендпойнти
    мусять давати пакетові однакові правила, а однакові вони лише з одного
    джерела: два списані блоки розійшлися б на першій же правці.
    АБЛЯЦІЯ ТЕПЕР ВІДТВОРЮВАНА В ОБОХ ЕНДПОЙНТАХ. Жереб вимкнених правил кидається
    від `сід` по кодах САМОГО брифа, тож `від_моделі` дістає ту саму половину
    правил, а не повний набір, як доти: доти суд другої ітерації не знав, що
    половину правил у запиті вимкнули.
    """
    вимк = list(d.get("вимкнені") or [])
    б_B = Б.бриф(п, T, гілка, вимкнені=вимк, вимоги=вимоги)
    # РЕЖИМ АБЛЯЦІЇ. Питання «яке саме правило працює» не має відповіді, поки всі
    # 20 правил їдуть разом у кожному прогоні: вони рухаються одним блоком, і
    # вердикт стосується блоку. Тут кожне правило вмикається монеткою, і те, які
    # саме випали, лягає в лог. Через N випадків кожне правило присутнє приблизно
    # в половині — і його внесок стає окремо оцінюваним. Ціна: одна рука більше
    # не є «продукт як він є», тому режим вимкнений за замовчуванням.
    if d.get("абляція"):
        import random as _r
        rnd = _r.Random(d.get("сід") or 0)
        коди = [p["код"] for p in б_B["правила"]]
        вимк = sorted(k for k in коди if rnd.random() < 0.5)
        б_B = Б.бриф(п, T, гілка, вимкнені=вимк, вимоги=вимоги)
    б_C = Б.бриф(пд, T_д, гд, інвертувати=інвертувати, вимкнені=вимк, вимоги=вимоги)
    # метал донора рахується з його ж рис і випадково збігався з металом B —
    # інверсія «навпаки від донора» поверталась у вихідне значення. Тому
    # перекидаємо відносно РУКИ B, а не відносно донора.
    if інвертувати:
        Б.перекинути_метал(б_B, б_C)
    return б_B, б_C, вимк


def запити(вхід):
    """Чотири запити на ОДИН і той самий випадок (план 2×2, 28.08.2026). Порядок перемішує стенд.

    ЧОМУ ПРАВИЛА ТЕПЕР ПО РУКАХ. У логу першого реального прогону (лог_1.json)
    стояв один список `правила` на весь випадок. Через це відповісти на питання
    «яке правило спрацювало» було неможливо в принципі: у рук без коду (3, 4)
    правил нема жодного, у C стоять ті самі мітки, але з ВИВЕРНУТИМИ значеннями.
    Один список на всі руки склеював різні стани в один. Тепер кожна рука несе
    свій набір із рядками, і перехресна таблиця «правило × рука × вердикт»
    рахується з логу без здогадів."""
    СЛ.почати()
    d = _json.loads(вхід) if isinstance(вхід, str) else вхід
    d = _застосувати_паспорт(d)
    # ── ГІЛКА Й СХЕМА БЕРУТЬСЯ З ОДНОГО МІСЦЯ З `від_моделі` (рядок 127) ──────
    # None = ЛЮДИНА НЕ ОБИРАЛА (доти будь-яка відсутність ставала нулем, і рангова
    # порада коду мовчки видавалась за людський вибір — див. brief.бриф); ім'я
    # сильніше за номер (рядок 117); пакет будується з `явні=(схема,)`, інакше
    # обраної гілки в розвилці може не бути зовсім. Усі три рішення стоять у
    # `міст_основи._пакет_гілки` — ОДНИМ виразом, який кличе і суд.
    # ВІДПОВІДІ ДРАПІРОВКИ З ПОКАЗУ. Приходять одним словником; двом споживачам
    # потрібні різні слова, тому переклад на СПІЛЬНІЙ межі (`_нормалізувати_вхід`),
    # а не в одному ендпойнті з трьох.
    d = _нормалізувати_вхід(d)
    текст = d["випадок"]
    вимоги = d.get("вимоги") or ""
    якір = _якір(d)
    намір = d.get("намір") or "conventional"

    F, T, зріст, kw = _збірка(d)
    п, гілка, схема_вибір, схема_підміна = _пакет_гілки(d, F, T, зріст, kw, якір, намір)
    if not п.get("готово"):
        return _json.dumps(dict(помилка=п.get("чому")), ensure_ascii=False)
    # ── K-IO-01 (19.09.2026): без сценарію не йде ЖОДНА рука — руки 3–4 ходять
    # без каталогу, але образ під невідому подію в них той самий. Композитор має
    # власний гейт для прямих викликачів; тут — той самий брак, тими ж словами,
    # ДО чотирьох промптів, а не після руки 1. `_застосувати_паспорт` вище вже
    # злив плитки з паспортом (`сценарій.з_показу`), тож читається результат злиття.
    import сценарій as _СЦ
    if not _СЦ.є_сценарій(d.get("сценарій")):
        # ЖІНЦІ — ПРАВДИВА ПРИЧИНА І ДІЯ (рядок 208, З-1а): відмова детермінована, і
        # показ доти казав «не дійшов звʼязок, спробуй за хвилину». Слова — тут, у
        # того, хто відмовляє; показ лише малює (`рядокЗбоюЗбирання`).
        return _json.dumps(dict(помилка=_СЦ.БРАК_СЦЕНАРІЮ, бракує=list(_СЦ.ВИЗНАЧАЛЬНІ),
                                правило="K-IO-01", жінці=_СЦ.БРАК_СЦЕНАРІЮ_ЖІНЦІ),
                           ensure_ascii=False)
    # ── ЖЕРЕБ ПОЛОМОК РУКИ 2 ──────────────────────────────────────────────
    # «палітра» вимагає розвилки хоча б на дві схеми; якщо її нема — поломка не
    # в наборі, і це кажеться назовні, а не мовчки пропускається.
    # ЖЕРЕБ, ДОНОР, ЗЛАМАНА ПАЛІТРА Й СЦЕНАРІЙ — В ОДНОМУ МІСЦІ (`_рука2`),
    # звідки їх бере і `від_моделі`: інакше рука 2 судилась не тим, чим складала.
    (поломки, F_д, T_д, пд, гд, сц2, текст2, псування, _дост,
     _поломка, _пасп2) = _рука2(d, гілка, F, T, п, зріст, kw, якір, намір,
                                схема_вибір=схема_вибір)
    _інв = "ремесло" in поломки
    # ОБИДВА БРИФИ Й АБЛЯЦІЯ — З ОДНОГО ДЖЕРЕЛА (`_брифи`): з Т-02 правила їдуть
    # у ПАКЕТ_V1, а пакет міряє бюджет, тож `від_моделі` мусить дістати рівно ті
    # самі правила, інакше пул суду розійдеться з пулом складання.
    б_B, б_C, вимк = _брифи(d, п, T, гілка, пд, T_д, гд, _інв, вимоги)

    перев = Б.перевірити_плацебо(б_B, б_C)
    # ЩО САМЕ РОЗВЕЛО РУКИ — НАЗВАНО, А НЕ ВГАДУЄТЬСЯ З ЧИСЛА. Відколи донор
    # став однією з випадкових поломок, «розбіжність 0.2» означає різне: або
    # плацебо сліпе, або цього разу рука 2 зламана НЕ донором. Ці два стани
    # нерозрізненні за одним числом, і саме тому тут стоїть підпис.
    перев = dict(перев, чим_розведено=sorted(поломки),
                 донор=("донор" in поломки),
                 придатне=(перев["придатне"] if "донор" in поломки else None),
                 чому=("плацебо міряє різницю ЛЮДИН лише коли випав «донор»; "
                       "цього разу рука 2 зламана так: " + ", ".join(sorted(поломки))))
    ф = п.get("форма") or {}
    # ── КАТАЛОГ У РУКИ B І C: код фільтрує, модель компонує з відфільтрованого ──
    # (28.08.2026, pipeline.пакет_для_моделі). Доти рука B діставала лише текст
    # умов і компонувала «з повітря» — жодна річ каталогу до моделі не доходила,
    # а весь рушій над каталогом до вердикту тестувальниці не потрапляв. Тепер,
    # коли стенд передає `каталог` (шлях до YML), B дістає кандидатів для ЦІЄЇ
    # людини, C — для ДОНОРА (плацебо лишається сліпим: інша людина — інші вікна,
    # інші речі). Рука A каталогу не бачить за визначенням (без правил).
    пак_B = пак_C = None
    # рука 2: сценарій трохи зіпсований — і в тексті випадку, і в композиторі (`_рука2`)
    # ЗІПСОВАНИЙ ТЕКСТ ВИПАДКУ ЇДЕ В `d2` (Т-02). Доти він жив лише в локальній
    # `текст2` і йшов у прозовий промпт руки 2. Відколи випадок став полем
    # `ПАКЕТ_V1.випадок.рядок`, шов бере його з `d` — і рука 2 дістала б
    # НЕЗІПСОВАНИЙ випадок, тобто жереб псування мовчки скасовувався б рівно в
    # тому полі, яке читає модель.
    # ТРАУР — ЗАЯВА ЛЮДИНИ (рядок 154): поломка «доречність» зсуває нагоду руки 2, але
    # трауру не оголошує й не скасовує — `траурний_регістр.з_заявою` кладе в її сцену
    # заяву людини, і регістр пулу, пакета й суду вмикає вона, а не нагода поломки.
    import траурний_регістр as _ТР
    d2 = dict(d, сценарій=_ТР.з_заявою(сц2, d.get("сценарій")), випадок=текст2, паспорт=_пасп2)
    # ПАСПОРТ РУКИ 2 — ТЕЖ ЗІПСОВАНИЙ (Т-11 крок 2, 12.09.2026). Т-02 записав цю
    # діру читанням і лишив рукам: псування жило в СЦЕНАРІЇ і в тексті випадку, а
    # паспорт лишався чистим — і паспорт переважає сценарій (`сценарій.з_показу`).
    # На живому шляху паспорт є завжди (виклик 0), отже «температура ±» і «година
    # ±» скасовувались самі: `вх["сценарій"]` діставав паспортне значення назад,
    # а `випадок.темп_c` у пакеті розходився з `випадок.рядок`. Тепер обидва боки
    # зсунуті однаково (`_зіпсувати_паспорт`), і рука 2 судиться тим, чим складалась.
    if d.get("каталог"):
        # ── ГІЛКА ЗА ЗАМОВЧУВАННЯМ (Н-V05-015) ───────────────────────────────
        # `гілка` лишається None там, де людина схеми не обирала: це розрізнення
        # потрібне `brief.бриф` (вона пропонує моделі ВСІ законні схеми) і
        # журналу. Але ПУЛ на союзі гілок лишав суддю без припису, тож сюди йде
        # перша гілка розвилки — і поруч їде прапорець, що це порада коду, а не
        # вибір людини. Рука C дістає те саме поводження з гілкою донора:
        # інакше два плеча складались би різними способами, і різниця між ними
        # перестала б бути тією поломкою, яку назвав жереб (`_рука2`).
        пак_B = _пакет_каталогу(d, F, T, п, (0 if гілка is None else гілка),
                               за_замовчуванням=(гілка is None), правила=б_B["правила"])
        пак_C = _пакет_каталогу(d2, F_д, T_д, пд, (0 if гд is None else гд),
                               за_замовчуванням=(гд is None), правила=б_C["правила"],
                               рука2=True)
        # ТУТ СКЛЕЮВАЛИ ДВА ТЕКСТИ: прозовий бриф правил + текст пакета. З Т-02
        # склеювати нема чого — правила лежать у `ПАКЕТ_V1.правила`, випадок у
        # `.випадок`, людина в `.людина`. `бриф["текст"]` лишається живим для
        # прогону БЕЗ каталогу (нижче) і для `перекинути_метал`.
    # БЕЗ ФОТО — НЕ ДЕФОЛТ, А ЗАЯВА НОСІЯ. Стенд артефакта фото до моделі не доносить
    # (виміряно), тому подає без_фото=1, і тоді ВСІ руки текстові. CLI, який фото
    # додати вміє, прапорця не подає й дістає попередню поведінку.
    бф = bool(d.get("без_фото"))
    _колір_рядок = Б.основний_колір(d.get("вибір_кольору") or (п.get("палітри") or {}).get("вибір_кольору"))
    # ── П'ЯТИЙ ПРОМПТ `A` ЗНЕСЕНО (V25, Т-11 крок 1) ──────────────────────────
    # План 2×2 має ЧОТИРИ руки, а `запити` будували п'ять текстів. Зайвий `A`
    # збігався з рукою 4 ПОБАЙТОВО, коли жінка кольору не обирала (виміряно:
    # 532 = 532 символи), і не читав його ніхто в дереві. Це не рука, а дубль,
    # який щоразу коштував побудови й плутав кожного, хто рахував руки з коду.

    def _рука_коду(пак, випадок_текст, бриф_):
        """Рука З КОДОМ: ПАКЕТ_V1 одним JSON-об'єктом (Т-02).

        БЕЗ КАТАЛОГУ ЛИШАЄТЬСЯ ПРОЗА, і це не другий контракт, а відсутність
        предмета: ПАКЕТ_V1 існує заради пулу, а пулу без каталогу нема — ні
        речей, ні номерів, ні гілок. Тоді рука дістає бриф умов, як доти, і
        просить образ прозою, яку читає той самий `образи_з_тексту`.
        ID ПРАВИЛ: у пакеті їх вирізав `_пакет_каталогу` (`_без_ід_глибоко`) —
        по рядкових ЗНАЧЕННЯХ, а не по готовому JSON; прозова гілка чиститься
        тут тим самим `_без_ід_рядків`, що й руки без коду.
        """
        if (пак or {}).get("готово") and пак.get("текст"):
            return пак["текст"]
        return _без_ід_рядків(Б.запит_B(випадок_текст, бриф_, вимоги,
                                        без_фото=бф, колір=_колір_рядок))

    B = _рука_коду(пак_B, текст, б_B)
    C = _рука_коду(пак_C, текст2, б_C)

    def _звірка_пакета(пак):
        """Розходження пакета зі схемою — назовні полем, а не в тишу (§1(б)).

        НЕ ВІДМОВА Й НЕ ВИНЯТОК: рука їде, а розходження їде поруч. Відмовляти
        руці на цьому кроці Т-02 не просить — там, де відмова потрібна (невалідна
        ВІДПОВІДЬ моделі), її вводить Т-04. Але відправити невалідний пакет МОВЧКИ
        означало б лишити рівно той стан, проти якого протокол і писався: невалідне
        невідрізненне від правильного. `None` — пакета не було (прогін без каталогу).
        """
        if not ((пак or {}).get("готово") and пак.get("пакет")):
            return None
        return _ПР.перевірити(_ПР.СХЕМИ["ПАКЕТ_V1"], пак["пакет"]) or None
    # руки 3 і 4: модель без коду — факти без висновків; лише сценарій
    # СПИСКИ ЙДУТЬ СПИСКАМИ. Раніше тут стояв str(): стенд подає шкіру трьома
    # точками, і в промпт руки 3 їхав пітонівський repr «['#f2d6c4', '#efd0bc']».
    # `факти_людини` сама зводить список до першого заміру й називає решту числом.
