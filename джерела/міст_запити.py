"""міст_запити.py — запити до моделі: брифи обох плечей, промпти чотирьох рук
   (`запити`), перетин пулів і розходження.

Виділено з `bridge.py` (19.09.2026, хвиля стандарту, СТАНДАРТ_КОДУ п.16) ЧИСТИМ
перенесенням: кожна функція й константа — байт у байт, разом із коментарями над
нею. `bridge.py` лишається фасадом і реекспортує кожне ім'я звідси; цей модуль
`bridge` не імпортує.
"""
import json as _json
import brief as Б
import trace as СЛ
import протокол as _ПР
from міст_вхід import (
    _волосся, _збірка, _якір, _нормалізувати_вхід, _застосувати_паспорт, _без_ід_рядків)
