# ── ЩО З ПОЛОМКИ ДІЙШЛО ДО МОДЕЛІ ────────────────────────────────────────────
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. `контроль.різних` рахує ЛИШЕ рядки брифа, і з шести
