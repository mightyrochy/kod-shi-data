# контроль на 5 сідах із 12. Виміряно на `каталог_brief.xml`, стендовий паспорт,
# сіди 0–11: до — «різних=0» на сідах 2, 3, 5, 8, 9; після — на тих самих сідах
# пакет руки 2 відрізняється від руки 1 полями `case` (нагода «робота» →
# «траур»), `day` (година, температура), `required_kinds` і `coat_required`
# (−9.8 °C вимагає верхнього шару), `poles`/`poles_unavailable`, `kind_notes`,
# `task`. Тобто сліпим був не прогін, а прилад.
# ЧОМУ ПУЛ І КРАМНИЦІ ПОЗА ЦИМ ЧИСЛОМ. `СІЛЬ_РУКИ_2` навмисно переставляє
# РІВНЕ в кожному слоті руки 2 (`міст_рука2`), отже `пул` і похідні від нього
# `магазини` різняться на КОЖНОМУ сіді незалежно від поломки. Порахувати їх тут
# означало б зробити «контроль не сліпий» завжди істинним — дзеркальна брехня до
# тієї, яку це лагодить. Пул міряється своїм числом — `пул_спільних`.
# КЛЮЧІ ТУТ ВНУТРІШНІ (аудит/ПРОДУКТ.md п.12): `пак["пакет"]` — словник внутрішньою
# мовою, англійські імена (`pool`, `shops`) з'являються пізніше, на збирачі
# промптів. Перелік англійськими іменами не виключив би тут нічого.
ПОЗА_СЛІДОМ = ("пул", "магазини")


def _ярлик_тіла(T):
    """Ярлик маршруту фігури (`fit.зони`) або None, коли чотирьох обхватів нема."""
    о = (T or {}).get("обхвати") or {}
    if not all(о.get(к) for к in ("плечі", "груди", "талія", "стегна")):
        return None
    return _ПС.зони(T)["ярлик"]


def слід_поломки(пак_B, пак_C):
    """Поля ПАКЕТ_V1, якими рука 2 відрізняється від руки 1. None — пакета не було."""
    a = ((пак_B or {}).get("пакет") if (пак_B or {}).get("готово") else None)
    b = ((пак_C or {}).get("пакет") if (пак_C or {}).get("готово") else None)
    if not isinstance(a, dict) or not isinstance(b, dict):
        return None
    return sorted(к for к in set(a) | set(b)
                  if к not in ПОЗА_СЛІДОМ and a.get(к) != b.get(к))


def перетин_пулів(пак_B, пак_C):
    """Скільки речей спільні в пулах рук 1 і 2 (Н-V25-052).

    Пул — це те, з чого модель узагалі має з чого обирати; коли поломка руки 2
    його не зрушила, різниця вердиктів 1↔2 не може бути різницею РЕЧЕЙ, і це
    треба знати з рядка журналу, а не відновлювати прогоном. `None` — каталогу
    в цей прогін не подано, отже пулів нема й міряти нічого.
    """
    ід = lambda пак: {str(r.get("id")) for сл in ((пак or {}).get("кандидати") or {}).values()
                      for r in (сл or []) if isinstance(r, dict) and r.get("id")}
    if not ((пак_B or {}).get("кандидати") and (пак_C or {}).get("кандидати")):
        return None
    return len(ід(пак_B) & ід(пак_C))


def розходження(pB, pC):
    """Правило за правилом: чи різниться рядок між рукою B і плацебо C.
    Правило, однакове в обох, сліпе — жоден вердикт про нього нічого не скаже."""
    C = {p["код"]: p["рядок"] for p in pC}
    різні = [p["код"] for p in pB if C.get(p["код"]) != p["рядок"]]
    сліпі = [p["код"] for p in pB if C.get(p["код"]) == p["рядок"]]
    return dict(різних=len(різні), сліпих=len(сліпі), різні=різні, сліпі=сліпі)
