def нота_розриву(слот):
    """Рядок вимог про єдиний слот, де колір поза палітрою дозволено (з записом у «свідомо»)."""
    return "Ламати палітру можна лише в слоті «%s» і лише з записом у «свідомо»." % слот


def образ_рядком(о, кандидати=None, ном=None):
    """«взуття: #12·33 Босоніжки… · низ: #45·10 Штани…» — образ зі СЛОТАМИ.

    ЧОМУ (02.09.2026, прогін 21:24: три образи поспіль із двома взуттями).
    Доти образ друкувався голими id: «ж-04756@miraton.ua, ж-00132@gepur.com».
    Модель не бачила, який id — взуття, тож коли вітрина ремонту пропонувала
    інше взуття, вона ДОДАВАЛА його, а не заміняла: замінити означало б
    вгадати, який із голих id прибрати. А до правки нумерації вітрини 02.09
    додане взуття не резолвилось узагалі й випадало мовчки — тому «раніше
    такого не було»: помилка була, її не було видно.
    Тепер кожна річ образу підписана слотом і номером із того самого пулу,
    що бачить модель, — замінити взуття означає замінити рядок «взуття: …»."""
    частини = []
    за_ід = {}
    for сл, пул in (кандидати or {}).items():
        for r in пул:
            if r.get("id"): за_ід.setdefault(r["id"], (сл, r.get("назва") or ""))
    for і in (о.get("ід") or []):
        сл, назва = за_ід.get(і, ("?", ""))
        мітка = ("#%d·%s" % ном[і]) if ном and і in ном else str(і)
        частини.append(("%s: %s %s" % (сл, мітка, назва[:40])).rstrip())
    return " · ".join(частини) if частини else ", ".join(str(x) for x in (о.get("ід") or []))


# ── ВКАЗІВКА МОДЕЛІ НЕ ЙДЕ НА КАРТКУ (доповнення рядка 210, 24.09.2026) ──────
# ЩО БУЛО. Рядок структурного блокера служить ДВОМ читачам: моделі (промпт ремонту
# `_шапка_вибору`) і жінці (`неповний` на картці). Через це на картку доїжджала
# вказівка для моделі: «…лиши комплект або візьми половину, СКАЗАВШИ СВІДОМО»
# (`суд_від_моделі`). «СВІДОМО» — назва поля протоколу, а не слово для людини
# (CLAUDE.md п.7: машинних слів на екрані нема), і рядок до того ж не мав крапки,
# тож злипався з наступним реченням картки: «…сказавши СВІДОМО СВІДОМО Шари…».
# ЩО ТЕПЕР. Рядок МОДЕЛІ лишається як був — його логіки я не чіпаю (п.1). Чистка
# стоїть на останньому ярусі перед очима жінки, тим самим ходом, що
# `показ.безМашинногоСліду`: вказівку знято, речення закрито крапкою.
_ВКАЗІВКА_МОДЕЛІ = _re_вк.compile(r",?\s*сказавши\s+СВІДОМО\b", _re_вк.I)
_СВІДОМО_СЛОВОМ = _re_вк.compile(r"\bСВІДОМО\b")
# «SKU» — те саме машинне слово на екрані (п.7), і в тому самому рядку: «верх і низ
# в одному SKU». Жінці це «в одній речі»; рядок моделі лишається зі «SKU», бо для
# неї це однозначний термін.
_SKU_ЖІНЦІ = ((_re_вк.compile(r"\bв одному SKU\b"), "в одній речі"),
              (_re_вк.compile(r"\bSKU\b"), "речі"))


# ── КАРТКА — ЛЮДИНІ, ЗВІТ — БЕЗ СТЕЛІ (рядок 210, 24.09.2026) ───────────────
# ЩО БУЛО. Рядок «Образ неповний…» на картці був ЗЛІПКОМ УСІХ блокерів через «; »,
# а блокер дубля слота перелічує КОЖНУ РІЧ поіменно. На великому неповному образі
# (стенд SLABKA=latynytsia, сід 7, 45 речей) виходило 2127 символів — стіна тексту
# на пів екрана 390×844, і та сама пояснювальна кінцівка «образ носять по одній на
# слот: лиши одну» повторювалась у ній стільком разів, скільком сімей із дублем.
# Перелічувались саме РЕЧІ: по 8–12 назв на кожну сім'ю, до 40 символів кожна.
# ЩО ТЕПЕР. Жінці — одне-два зрозумілі речення: ЩО не так (згруповано за видом
# блокера, не за річчю) і ЩО зробити. Назв речей на картці нема: слот назвати
# корисно («по кілька речей на взуття й сумку» — це дія), назвати дванадцять
# черевиків — ні. Повний перелік не гине: він іде в `чому`, тобто у звіт власника
# («Скопіювати всі вердикти», `показ.html`: колонка `неповний` читає
# `неповний_чому`). Рішення власника: звіт без стелі, картка — для людини.
_БЛОКЕРІВ_НА_КАРТЦІ = 3        # п.9: групувати до трьох тем, а не висипати всі
_РЕ_СІМ_Я = _re_вк.compile(r"у сім'ї «([^»]+)»")
# ДРУГЕ «ОБРАЗ НЕПОВНИЙ» ПОСЕРЕД РЕЧЕННЯ (рядок 210, 25.09.2026). Рядок картки
# починається з «Образ неповний: », а один блокер (`суд_від_моделі`: «образ
# неповний: 3 речі, а для нагоди потрібно щонайменше 4») несе ту саму шапку в
# собі — і на картці виходило «Образ неповний: нема сумки …; ОБРАЗ НЕПОВНИЙ: 3
# речі…». Давнє, не від згортання: зліпок через «; » просто ставив дві шапки в
# одне речення. Рядок для МОДЕЛІ лишається як був (у промпті ремонту блокер
# стоїть окремо, і шапка в ньому доречна) — знімаємо її на останньому ярусі
# перед очима жінки, як і решту гігієни цього рядка. «у ньому» замість шапки:
# без нього клауза почалася б числом («…обов'язкова; 3 речі, а для нагоди…»).
_РЕ_ДРУГА_ШАПКА = _re_вк.compile(r"^\s*образ\s+неповний\s*:\s*", _re_вк.I)
# Знахідний відмінок після «на» — ЗАКРИТИМ ПЕРЕЛІКОМ, а не за закінченням.
# Правило «-а→-у, -я→-ю» тут не працює: «сукня» жіноча («на сукню»), а «взуття»
# СЕРЕДНЬОГО роду, і в знахідному лишається «взуття» — не «взуттю». Словник слотів
# закритий (`суд_від_моделі.СЛОТИ_БЛОКЕРА` + під-слоти прикрас), тож його й
# перелічуємо; те саме рішення, що для дієслів у `паспорт_нагоди` (рядок 210).
_СЛОТ_НА = {"сумка": "сумку", "сукня": "сукню", "брошка": "брошку",
            "каблучка": "каблучку"}


def _переліком(слова):
    """«взуття, сумку і верх» — кома між усіма, «і» перед останнім."""
    с = list(dict.fromkeys(x for x in слова if x))
    return с[0] if len(с) == 1 else "%s і %s" % (", ".join(с[:-1]), с[-1]) if с else ""


def _слот_кого(слот):
    """Ім'я слота після «на»: підкреслення — пробілом, жіночі — у знахідному."""
    с = str(слот or "").replace("_", " ").strip()
    return _СЛОТ_НА.get(с, с)


def _коротко_жінці(блокери):
    """Рядок «Образ неповний…» для КАРТКИ: без назв речей і без повторів.

    ЗГОРТАЄТЬСЯ ЛИШЕ ТЕ, ЩО РОЗДУЛОСЬ. Стіну робив ОДИН вид блокера — дубль
    слота: він перелічує кожну річ поіменно (по 8–12 назв на сім'ю) і повторює
    кінцівку «образ носять по одній на слот» стільком разів, скільком сімей.
    Усі такі блокери стають одним рядком, який називає СЛОТИ, не речі: слот —
    це дія («лиши по одній на взуття й сумку»), дванадцять назв черевиків — ні.
    Решта блокерів лишається СВОЇМИ словами: «нема сумки — для цієї нагоди
    сумка обов'язкова», «потрібна ще одна річ понад верх, низ і взуття:
    верхній шар, прикраса, пояс, шарф або головний убір» — це вже одне коротке
    речення й воно корисне, переписувати його означало б забрати в жінки
    названий вихід. Повний перелік (з назвами) лишається у звіті власника.

    `блокери` — dict'и з `код`/`суть` (`структура.блокери`) або самі рядки суті:
    код тоді виводиться з тексту (`_код_блокера`)."""
    дублі, решта = [], []
    for b in блокери or []:
        суть = _без_вказівки_моделі(str((b or {}).get("суть") or "") if isinstance(b, dict)
                                    else str(b or ""))
        код = ((b or {}).get("код") if isinstance(b, dict) else None) or _код_блокера(суть)
        if код == "слот_двічі":
            м = _РЕ_СІМ_Я.search(суть)
            дублі.append(_слот_кого(м.group(1)) if м else None)
        elif суть:
            решта.append(_РЕ_ДРУГА_ШАПКА.sub("у ньому ", суть))
    частини = ([("по кілька речей на %s — лиши по одній у кожному слоті" % _переліком(дублі))
                if any(дублі) else "кілька речей на один слот — лиши по одній"] if дублі else [])
    частини += решта
    більше = len(частини) - _БЛОКЕРІВ_НА_КАРТЦІ
    частини = частини[:_БЛОКЕРІВ_НА_КАРТЦІ]
    if not частини:
        return None
    return ("Образ неповний: " + "; ".join(частини)
            + ((" — і ще %d, %s у звіті" % (більше, "вони" if більше > 1 else "воно"))
               if більше > 0 else ""))


def _без_вказівки_моделі(суть):
    """Суть блокера без слів, адресованих МОДЕЛІ. Те, що лишилось, — про образ."""
    т = _ВКАЗІВКА_МОДЕЛІ.sub("", str(суть or ""))
    т = _СВІДОМО_СЛОВОМ.sub("", т)
    for шаб, чим in _SKU_ЖІНЦІ:
        т = шаб.sub(чим, т)
    return _re_вк.sub(r"\s{2,}", " ", т).strip(" ,;:")


def _реченням(рядок):
    """Рядок для картки, закритий крапкою: без неї він злипається з наступним."""
    т = " ".join(str(рядок or "").split()).rstrip(" ,;:")
    return (т + ".") if т and т[-1] not in ".!?…" else т


def _код_блокера(рядок):
    """Код структурного блокера зі слів `структура_образу`, або None для не-структурного.

    Слова — ті самі, за якими показ вирізняє структурні рядки з `блокує`
    (показ.html: «по одній на слот|аксесуари, а не образ|подвоєн|з однієї речі»):
    вони вже були контрактом, тут він названий одним місцем. Рядки гейтів коду не
    мають навмисно: гейт — знахідка з регістром «гейт», і живе у `знахідки`."""
    т = str(рядок or "")
    if "по одній на слот" in т or "подвоєн" in т:
        return "слот_двічі"
    if "аксесуари, а не образ" in т:
        return "нема_верху_низу"
    if "з однієї речі" in т:
        return "одна_річ"
    if "нема взуття" in т:
        return "нема_взуття"
    if "нема сумки" in т:
        return "нема_сумки"
    if "нема верхнього шару" in т:
        return "нема_верхнього_шару"
    if "потрібна ще одна річ" in т or "образ неповний" in т:
        return "неповний"
    return None


def _шапка_вибору(образи, випадок=None, скільки_свідомих=2, кандидати=None):
    """Шапка промпта вибору: рядки з результатом перевірки кожного образу (склад, свідомі
    ходи, блокери, перші знахідки) — список рядків для `промпт_вибору`."""
    р = ["Код перевірив твої допрацьовані образи. Ось результат."]
    if випадок:
        р.append("ВИПАДОК: %s" % випадок)
    _ном = номери_речей(кандидати)[0] if (кандидати and ПАКУВАТИ_ІНДЕКСОМ) else None
    for i, о in enumerate(образи or [], 1):
        р.append("")
        р.append("── образ %d%s: %s" % (i, (" · %s" % о["підпис"]) if о.get("підпис") else "",
                                        образ_рядком(о, кандидати, _ном)))
        for с in (о.get("свідомі") or [])[:скільки_свідомих]:
            # запис образу несе оголошення обʼєктом (`bridge._вердикти_образів`);
            # рядок лишається робочим входом — прозовий стенд кладе сюди рядки
            р.append("    СВІДОМО (твій оголошений хід): %s"
                     % (с.get("текст") if isinstance(с, dict) else с))
        for б in (о.get("блокує") or [])[:4]:
            р.append("    БЛОКУЄ: %s" % (б if isinstance(б, str) else б.get("суть", б)))
        for з in (о.get("знахідки") or [])[:5]:
            р.append("    · %s%s" % ((з.get("суть") or ""),
                                     " ← оголошений хід" if з.get("свідомий") else ""))
    return р


def _рядки_режиму_фото(без_фото):
    """(роль, рамка до пунктів, хвіст після пунктів) — рядки промпта вибору, що
    залежать від того, чи є в моделі фото людини.

    ОДИН СВІДОК (K-IO-04, рядок 105 дошки, 20.09.2026). Доти `промпт_вибору`
    брав `без_фото` й не читав його: виклик 3 їхав тим самим текстом з фото й
    без, а «без входу» ≠ «пройдено». Перемикач — ТОЙ САМИЙ, що в `brief.запит_В`
    / `запит_B`: прапорець обирає пару констант (`ЗАВДАННЯ_БЕЗ_ФОТО`,
    `ФОРМАТ_ЛИШЕ_ТЕКСТ`) або (`ЗАВДАННЯ`, `ФОРМАТ`); тексту про фото тут не
    дописано жодного рядка. Із завдання береться ПЕРШИЙ рядок — хто модель і чи
    додано фото людини (другий, «склади образ», тут не діє: образи вже складені
    й перевірені кодом); з формату — усе, КРІМ пунктів 1–3 опису: рамка до них
    («ТІЛЬКИ ТЕКСТ, без зображення» / «ДВОМА ЧАСТИНАМИ … ЧАСТИНА 1 — ТІЛЬКИ
    ТЕКСТ») і хвіст після них (з фото — частина 2 на основі фото людини, де на
    ньому нічого не міняється; в обох режимах — заборона чисел світлоти й типів
    фігури, лише українська). Пункти 1–3 — свої, нижче: проза для жінки, колір
    словами, без hex — рішення промпта вибору, не формату рук."""
    import brief as _Б
    зав, фор = ((_Б.ЗАВДАННЯ_БЕЗ_ФОТО, _Б.ФОРМАТ_ЛИШЕ_ТЕКСТ) if без_фото
                else (_Б.ЗАВДАННЯ, _Б.ФОРМАТ))
    рядки = фор.splitlines()
    пункти = [i for i, l in enumerate(рядки) if l[:2] in ("1.", "2.", "3.")]
    return зав.splitlines()[0], рядки[:пункти[0]], рядки[пункти[-1] + 1:]


def промпт_вибору(образи, випадок=None, без_фото=True):
    """Третій виклик СТЕНДА: один образ і опис для людини одним викликом.

    Лишається як було — його читає шаблон стенда, якого ця правка не торкалась.
    Показ ходить не ним: з Т-06 виклик 3 — це `ВЕРДИКТ_V1` із `завдання.відповідь=
    "ВИБІР_V1"` (`вердикт_вибору`), виклик 4 — `ОПИС_V1` (`опис_v1`).

    `без_фото` — той самий прапорець, що вмикає текстовий режим рук у `brief`
    (`міст_відповіді.відповідь` шле `d["без_фото"]`, показ — `без_фото: 1`):
    рядки, що залежать від фото, дає `_рядки_режиму_фото`, і лише вони."""
    роль, рамка, хвіст = _рядки_режиму_фото(без_фото)
    р = [роль] + _шапка_вибору(образи, випадок)
    р += [
        "",
        "Обери ОДИН образ — той, за який ти ручаєшся перед цією жінкою. Не той, до "
        "якого менше зауважень: той, який ти вважаєш найкращим для неї й цього випадку.",
        "Далі опиши його для неї:",
    ]
    р += рамка
    р += [
        # ПРОЗА — ДЛЯ ЛЮДИНИ, НЕ ДЛЯ МАШИНИ. Тут стояло «колір + hex», і модель
        # слухняно писала «графіт #4a4a4a», а поруч у рядку речі — повний id із
        # доменом магазину. Тестувальниця судить, чи вона це вдягне: адреси в
        # каталозі й шістнадцяткові коди їй не потрібні й читаються як збій.
        # Машинний хвіст лишається — але рівно один рядок, в кінці.
        "1. Речі — по рядку на кожну: що це, крій, довжина, колір словами, тканина.",
        "2. Взуття, верхній шар, аксесуари.",
        "3. Чому це працює — 3–4 речення.",
        "Останнім рядком — «ОБРАЗ: id, id, …».",
        "У самому описі НЕ пиши id речей і НЕ пиши hex-коди — лише людські слова. "
        "Id потрібні тільки в останньому рядку «ОБРАЗ:».",
        "Якщо в образі є щось нестандартне — як саме це носити, окремим рядком "
        "«СВІДОМО: <що> — <чому>». Цей рядок жінка побачить як пораду.",
    ]
    # хвіст формату: з фото — частина 2 (зображення на основі фото людини), далі
    # в обох режимах — «не називай чисел світлоти, типів фігури…, лише українською»
    # (доти цей рядок стояв тут власною копією; тепер він із `brief`, як і решта)
    р += хвіст
