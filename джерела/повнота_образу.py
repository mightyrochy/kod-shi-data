def злити_з_неторканими(відповідь, попередній):
    """ОБРАЗИ_V1 ремонту повноти до вибору + вердикт, з яким рука пішла в ремонт → ОБРАЗИ_V1
    з УСІМА образами вердикта в його порядку: образ, який модель повернула (за «ід», а коли
    ід не той — за найбільшим перетином речей, а в нічиї — за меншою різницею складу), — її складом; решта — складом вердикта, з її
    ж підписом, «днем» і оголошеними ходами. Образи відповіді, яким пари нема, — наприкінці.

    `(обʼєкт, неторканих)`; None, коли у відповіді нема жодного образу: тоді рука лишається
    на вердикті ремонту, як на будь-якій відповіді без образів."""
    обр = [о for о in ((відповідь or {}).get("образи") or []) if isinstance(о, dict)]
    поп = [о for о in ((попередній or {}).get("образи") or []) if isinstance(о, dict)]
    if not обр or not поп:
        return None
    _н = lambda о: {str(r).split("/")[0] for r in (о.get("речі") or [])}
    взято, пари = set(), {}
    for к, о in enumerate(обр):
        п = next((j for j, х in enumerate(поп) if j not in взято
                  and str(х.get("ід") or "") == str(о.get("ід") or "")), None)
        if п is None:
            # Нічия перетину — пара з меншою різницею складу (рядок 1987): ремонт додає чи знімає
            # річ-дві, тож його образ — найближчий за складом, а не перший за порядком вердикта.
            п = max((j for j in range(len(поп)) if j not in взято),
                    key=lambda j: (len(_н(поп[j]) & _н(о)), -len(_н(поп[j]) ^ _н(о)), -j), default=None)
            if п is not None and not (_н(поп[п]) & _н(о)):
                п = None
        if п is not None:
            взято.add(п)
            пари[п] = к
    вих = []
    for j, х in enumerate(поп):
        # «Change nothing else» (`ПОВНОТА_ВСІ`): підпис, «день» і оголошення образу, яких
        # відповідь не повторила, — ті самі, що у вердикті; оголошення про річ, якої в
        # складі вже нема, розбір знімає сам (`_свідомі_з_json(склад=…)`).
        був = {к: v for к, v in dict(
            підпис=х.get("підпис"), речі=list(х.get("речі") or []), день=х.get("день"),
            свідомо=[dict(річ=с.get("річ"), чому=с.get("чому")) for с in (х.get("свідомі") or [])
                     if isinstance(с, dict) and (с.get("річ") or с.get("чому"))]).items() if v}
        if j in пари:
            вих.append(dict(був, **{к: v for к, v in обр[пари[j]].items() if v and к != "ід"},
                            ід=str(х.get("ід") or "")))
            continue
        вих.append(dict(був, ід=str(х.get("ід") or "")))
    вих += [о for к, о in enumerate(обр) if к not in пари.values()]
    return dict(версія=str((відповідь or {}).get("версія") or "1"), образи=вих), len(поп) - len(пари)


# Блокери, які лікує ремонт повноти: порожній слот (`СЛОТИ_БЛОКЕРА`) і слот із кількома
# речами. Вето, одна річ і гейти — не його задача.
_БЛОКЕРИ_ПОВНОТИ = frozenset(СЛОТИ_БЛОКЕРА) | {"слот_двічі"}


def _коди_структури(о):
    """Коди структурних блокерів образу вердикта."""
    return {str((b or {}).get("код") or "") for b in ((о.get("структура") or {}).get("блокери") or [])
            if isinstance(b, dict)}


def _бракує_адресно(образи, потрібні, вітрина):
    """`бракує` другої спроби: на образ — його склад, порожні слоти з трьома речами вітрини,
    що їх закривають, і групи речей, які ділять один слот. Внутрішньою мовою: номери й
    слоти, без речень (аудит/ПРОДУКТ.md п.12)."""
    за_образом = {}
    for слот, іди in (потрібні or {}).items():
        for ід in іди:
            за_образом.setdefault(str(ід), []).append(слот)
    вих = []
    for о in образи:
        ід = str(о.get("ід") or "")
        порожні = {с: [r.get("н") for r in ((вітрина.get(с) or [])[:3])] for с in за_образом.get(ід, [])}
        двічі = [list(b.get("речі") or []) for b in ((о.get("структура") or {}).get("блокери") or [])
                 if isinstance(b, dict) and b.get("код") == "слот_двічі"]
        if порожні or двічі:
            вих.append(dict(образ=ід, речі=list(о.get("речі") or []),
                            **({"порожні": порожні} if порожні else {}),
                            **({"двічі": двічі} if двічі else {})))
    return вих


def вердикт_повноти(вердикт, спроба=1, всі=False):
    """Дані промпта ремонту повноти: той самий вердикт ітерації 2, звужений до образів із
    блокером повноти (порожній слот чи кілька речей в одному). Повідомлення з них будує
    збирач (`ПОВНОТА`, `міст_відповіді`).

    `спроба` — котрий це виклик ремонту повноти на цю руку (1 або 2). Друга несе
    `бракує`: перше прохання ші вже чула.

    `всі` — ремонт ДО вибору (`ПОВНОТА_ВСІ`): ті самі образи з дірами, але модель доповнює
    кожен, тож порядок «образ без гейта першим» тут не потрібен.

    None, коли лікувати нема чого: образів із такими блокерами нема, або всі вони чекають
    лише порожнього слота, а вітрина його не несе, — тоді й зайвого виклику до моделі нема.
    """
    в = dict(вердикт or {})
    образи = [о for о in (в.get("образи") or [])
              if isinstance(о, dict) and (_коди_структури(о) & _БЛОКЕРИ_ПОВНОТИ)]
    if not образи:
        return None
    вітрина = в.get("вітрина") or {}
    # ОБРАЗ БЕЗ ГЕЙТІВ — ПЕРШИМ (рядок 146): модель доповнює ОДИН, і коли перший у
    # переліку ще й несе гейт (річчю він не лікується), ремонт закінчується образом,
    # якого код однаково не прийме. Виміряно на «+5, дощ», сід 3, рука 2: п'ять
    # образів без пальта, перший — із K-PAL-03, а образ без гейта губився.
    if not всі:
        образи.sort(key=lambda о: 1 if _чому_не_можна(dict(о, структура=dict(ок=True, блокери=[])))
                    else 0)
    потрібні, _чому = _слоти_повноти(образи, вітрина)
    if not потрібні and not any("слот_двічі" in _коди_структури(о) for о in образи):
        return None
    # ОБРАЗ ТУТ — СКЛАД З ОПИСАМИ РЕЧЕЙ І СТРУКТУРА: знахідки, чекліст і вузол до питання
    # повноти стосунку не мають, а важать більшу частину промпта ремонту. Описи — бо модель
    # вирішує, котру з двох речей лишити, і речі, які отримує модель, — завжди з описом
    # (рішення власника 25.09).
    # «день» — її речення про день цього образу (КОМПЛЕКТ-1, рядок 1417): без нього модель
    # писала в обов'язкове «day» відповіді коди випадку («office_corporate, formality 6-8»), 22
    # з 25 образів, і вони йшли у вибір як її речення.
    в["образи"] = [{k: v for k, v in о.items() if k in ("ід", "підпис", "речі", "описи", "день", "структура")}
                   for о in образи]
    for ключ in ("набір", "мова", "реєстр", "завдання"):
        в.pop(ключ, None)
    # ВІТРИНА ЗВУЖУЄТЬСЯ ДО СЛОТІВ ПОВНОТИ: вузли напруги тут не питання, а зайвий
    # виклик має бути найдешевшим із тих, що працюють.
    в["вітрина"] = {с: р for с, р in вітрина.items() if с in потрібні}
    if int(спроба or 1) >= 2:
        в["бракує"] = _бракує_адресно(в["образи"], потрібні, в["вітрина"])
    return в


# ── РЕМОНТ ПОВНОТИ НЕ МАЄ ПРАВА ГУБИТИ РЕЧІ, ПРО ЯКІ ЙОГО НЕ ПРОСИЛИ (рядок 150) ──
# ЩО БУЛО ЗЛАМАНО (доповідь ноутбука 25.09, gemma, сід 13, рука 2). `ПОВНОТА` вище
# КАЖЕ моделі «Change nothing else: the remaining items and the caption stay as they
# are» — і на цьому все: склад, який повернула відповідь ремонту, ставав складом образу
# ЦІЛКОМ, бо вердикт будується з відповіді (`міст_відповіді._вердикти_образів`), а з чим
# образ ішов у ремонт, після цього не питають ніде. Слабка модель, доповнюючи ОДИН слот,
# перепише склад коротше — і прикраси з сумкою зникають із картки, хоч блокер просив
# інше. Виміряно на доповіді: прикрас 4 → 1, сумок 2 → 1, і жодного рядка про втрату.
# Той самий урок, що вже записаний про поради в розмові (аудит/ПРОДУКТ.md п.9):
# НЕІНВАЗИВНІСТЬ ЗАБЕЗПЕЧУЄ КОД, НЕ ПОБАЖАННЯ МОДЕЛІ.
# ПРАВИЛО ОДНЕ, І ВОНО ТОЧНО ТАКЕ, ЯК ПРОХАННЯ В ПРОМПТІ: річ, що стояла в образі до
# ремонту, вертається в нього, ЯКЩО в складі після ремонту НЕМА іншої речі її сім'ї слота
# (`_сім_я_слота` — та сама, якою `структура_образу` рахує «по одній на слот»). Через це
# окремого випадку для «слот_двічі» не треба: модель, яку просили звести сім'ю до однієї
# речі, лишає в ній одну — сім'я зайнята, решта не вертається; а коли вона винесла із
# сім'ї ВСЕ, вертається рівно одна річ, і діра, якої ремонт не просив, не з'являється.
# Заміна теж лишається за моделлю: поклала у сім'ю іншу річ — сім'я зайнята, стара не
# лізе назад другою. Вертається річ ТОГО САМОГО образу: пара «відповідь ↔ образ до
# ремонту» зводиться найбільшим перетином складу, тим самим ключем, що
# `вердикт_моделі._зіставити_образи`.
def _склади_до_ремонту(попередній, ном):
    """Образи вердикта, з яким рука пішла в ремонт: `[(ід, склад id, день)]`."""
    за_ном = {"#%d·%s" % v: k for k, v in (ном or {}).items()}
    return [(str(о.get("ід") or ""), [за_ном[н] for н in
                                     (str(r).split("/")[0] for r in (о.get("речі") or []))
                                     if н in за_ном], о.get("день"))
            for о in ((попередній or {}).get("образи") or []) if isinstance(о, dict)]


def дні_до_ремонту(набори, попередній, ном):
    """Речення «день» образу до ремонту повноти — на кожен склад відповіді (None, коли пари
    нема). Ремонт повноти дня не міняє (КОМПЛЕКТ-1, рядок 1417): модель писала туди коди
    випадку, і вони йшли у вибір як її речення; день лишається її реченням з образу до
    ремонту — пара зводиться найбільшим перетином складу, як у `дотримати_склад`."""
    поп = _склади_до_ремонту(попередній, ном)
    вих = []
    for н in (набори or []):
        _і, був, день = max(поп, key=lambda п: len(set(п[1]) & set(н)), default=("", [], None))
        вих.append(день if (set(був) & set(н)) and день else None)
    return вих


def дотримати_склад(набори, попередній, ном, словник):
    """Склади відповіді ремонту повноти → ті самі склади з речами, яких ремонт не просив
    знімати. `(набори, повернуто)`; `повернуто` — `[{образ, річ, слот, сім_я}]` для звіту.

    `набори` — склади (id) з відповіді моделі; `попередній` — ВЕРДИКТ_V1, з яким рука
    пішла в ремонт (його `образи[].речі` — номери, як їх бачила модель); `ном` — `id →
    (номер, код)` (`пакет_моделі.номери_речей`); `словник` — `id → {слот, назва}` пулу
    й каталогу, з якого береться сім'я слота.

    Без попереднього вердикта, без номерів або коли перетину складів нема, віддає
    `набори` як є: вгадувати, що модель мала на думці, тут нема з чого.
    """
    поп = [(і, ск) for і, ск, _д in _склади_до_ремонту(попередній, ном)]
    сім = lambda і: _сім_я_слота((словник.get(і) or {}).get("слот"),
                                 (словник.get(і) or {}).get("назва"))
    вих, повернуто = [], []
    for н in (набори or []):
        склад = list(н)
        ід_о, був = max(поп, key=lambda п: len(set(п[1]) & set(склад)), default=("", []))
        if not (set(був) & set(склад)):
            вих.append(склад)
            continue
        зайняті = {сім(і) for і in склад}
        # КОМПЛЕКТ-1 (рядок 1411): ціла річ (сукня, комплект) сама закриває верх і низ, тож
        # знятий ремонтом верх чи низ поруч із нею назад не йде — інакше «зняти — повернути»
        # ходило колом, і блокер «комплект + верх» лишався. Виняток — верх під піджаком чи
        # жилетом комплекту (`склад_комплекту`): його суд не блокує, і повернути його можна.
        # КОМПЛЕКТ-2: так само верх поруч із комплектом НЕВІДОМОГО складу — суд там лише питає.
        _шар_компл = any(сім(і) == "комплект" and склад_комплекту(словник.get(і) or {})[0] != "верх"
                         for і in склад)
        if {"сукня", "комплект"} & зайняті:
            зайняті.add("низ")
            if not (_шар_компл and "сукня" not in зайняті):
                зайняті.add("верх")
        for і in був:
            с = сім(і)
            if і in склад or с in зайняті:
                continue
            склад.append(і)
            зайняті.add(с)
            повернуто.append(dict(образ=ід_о, річ=і, слот=(словник.get(і) or {}).get("слот"),
                                  сім_я=с, назва=(словник.get(і) or {}).get("назва")))
        вих.append(склад)
    return вих, повернуто


# ── ВИБІР, ЯКИЙ ВИДНО Й БЕЗ «обрано» (рядок 208, З-6) ────────────────────────
# Слабка модель відповідає на ВИБІР_V1 не тим ключем («відповідь»: «о1»), чужим
# записом ід («O1» латиницею, «образ 3», просто 3) або самим образом замість вибору
# ({ід: «образ_1», речі: […]}). Доти кожне з цього — «відповідь не прочитано»,
# повторний виклик, а слабка модель на повторі робить те саме, і рука падала в
# запасний образ коду, хоч модель СВІЙ вибір назвала. Тепер вибір читається, коли
# він ОДНОЗНАЧНИЙ: ід образу вердикта стоїть у рівно одному полі-кандидаті, або склад
# відповіді-образу рівно дорівнює складу одного образу вердикта. Ехо вхідного
# ВЕРДИКТ_V1 назад (З-6) вибором не є: його поля — поля вердикта, і їх не читаємо.
_НЕ_ВИБІР = frozenset(set(_ПР.ВИБІР_V1["поля"]) | set(_ПР.ВЕРДИКТ_V1["поля"])
                      | set(_ПР.ОБРАЗ_МОДЕЛІ["поля"])) - {"обрано", "ід"}
# Поля, які має лише ВЕРДИКТ: відповідь із ними — ехо входу, навіть коли обрив лишив
# у ній рівно один цілий образ (без цього обрізане ехо «обирало» перший образ).
# Перелік живе в протоколі (Т-7): той самий, яким розбір ОБРАЗИ_V1 знімає ехо ремонту,
# і з ним — список суду `вердикт` у формі на дроті (`протокол.поля_входу`).


def _ід_значенням(ключ, v, ідентифікатори):
    """Значення поля відповіді → ід образу вердикта, який воно однозначно називає.

    Число приймається лише в `обрано` (3 → «о3»): у будь-якому іншому полі воно
    може бути чим завгодно — «ітерація»: 2 у вердикті, переписаному назад."""
    if isinstance(v, (list, tuple)) and len(v) == 1:
        v = v[0]
    if isinstance(v, bool) or not isinstance(v, (str, int)) or (isinstance(v, int) and ключ != "обрано"):
        return None
    с = _re.sub(r"[\s#№«»\"'_\-.:]", "", str(v).strip().lower().replace("o", "о"))
    if с in ідентифікатори:
        return с
    м = _re.fullmatch(r"(?:о|образ|варіант)?(\d+)", с)
    return ("о" + м.group(1)) if м and ("о" + м.group(1)) in ідентифікатори else None


def _обрано_однозначно(об, вердикт, словник, за_ном):
    """→ (образ вердикта, як прочитано) або (None, None).

    Відповідь-ОБРАЗ судиться лише складом: її власне «ід» («образ_1») — імʼя, яке
    модель дала сама, і нумерація вердикта з ним не мусить збігатись."""
    if _ПР.поля_входу(об):
        return None, None
    образи = [о for о in ((вердикт or {}).get("образи") or []) if isinstance(о, dict)]
    за_ід = {str(о.get("ід") or ""): о for о in образи}
    речі = об.get("речі")
    if речі is None and isinstance(об.get("образи"), list) and len(об["образи"]) == 1 \
            and isinstance(об["образи"][0], dict):
        речі = об["образи"][0].get("речі")
    # Т-7: образ на дроті стоїть у «твій_образ» — «сам образ замість вибору» від
    # моделі, що бачила таку форму, приходить у тій самій обгортці
    if речі is None and isinstance(об.get(_ПР.ТВІЙ_ОБРАЗ), dict):
        речі = об[_ПР.ТВІЙ_ОБРАЗ].get("речі")
    if речі is not None:
        свій = set()
        for x in _список(речі):
            з, _н, _ч = _розпізнати_речі(str(x), словник, за_ном, поле=True)
            свій |= {і for і in з if і in словник}
        збіги = [о for о in образи if свій and set(_склад_вибору(о, словник, за_ном)["ід"]) == свій]
        if len(збіги) == 1:
            return збіги[0], ("вибір прочитано за складом: відповідь — сам образ, і його речі — "
                              "рівно речі «%s»" % збіги[0].get("ід"))
        return None, None
    знайдено = {}
    for к, v in об.items():
        if к in _НЕ_ВИБІР:
            continue
        ід = _ід_значенням(к, v, за_ід)
        if ід:
            знайдено.setdefault(ід, к)
    if len(знайдено) == 1:
        ід, к = next(iter(знайдено.items()))
        return за_ід[ід], "«обрано» прочитано з поля «%s»: «%s» → «%s»" % (к, об.get(к), ід)
    return None, None


