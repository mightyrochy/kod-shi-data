# Те саме для рядка ПРО КАТАЛОГ (ярус 3) з 26.09.2026 несе КОД структурної діри
# (`внутрішня_мова.ТАБЛИЦЯ["missing_part"]`), а не слово в родовому з «жодної»: відмінок і
# перелік («ні шарфа, ні пояса…») складає перекладачка (Ч-1, аудит/ПРОДУКТ.md п.12).


def _не_налізе(речі, було):
    """Чи річ, докладена кодом, дала новий гейт драбини шарів K-OUT-06 (рядок 158)."""
    import outer as _ВШ
    г = lambda рр: sum(1 for з in _ВШ.драбина_шарів(рр) if з.get("блокує"))
    return г(речі) > г(було)


def _дібрати_кодом(ід, частини, кандидати, словник, сценарій=None):
    """Закрити структурну діру складеного образу річчю з ТОГО САМОГО пулу.
    → `(ід із дібраним, [{id, слот, чому}], чому_ні)`.

    ПОРЯДОК КАНДИДАТІВ НЕ ПЕРЕВИЗНАЧАЄТЬСЯ. Пул слота вже впорядкований
    композитором: ключ сорту — колірна відстань до центру вікна, а речі запасної
    хвилі (`_доповнено`, у пакеті — `у_дузі: false`) дістають +100, тобто стоять
    після ядра. Це рівно той порядок, у якому пул бачить ші. Другий сорт тут
    означав би, що код і модель звуть «найкращим» різні речі.
    ОДИН ВИНЯТОК (рядок 146): верхній шар пальтової зони береться з
    `суд_погода.пальта_пулу` — лише речі, які в образі справді стануть верхнім
    шаром, і теплі першими; усередині класу тепла порядок пулу той самий. Інакше
    першим ішов би піджак («+5, дощ»: перші дві речі слота — піджак і кардиган).

    ПРИЙМАЄТЬСЯ ЛИШЕ ПОВНЕ ЗАКРИТТЯ. Образ, у який код доклав річ і все одно не
    прийняв, бреше двічі: жінці — рядком «дібрав код», і собі — «полагоджено».
    Тому при невдачі відкат повний, а `чому_ні` називає, на чому стало.
    """
    import реєстр_правил as _РЕЄСТР, суд_погода as _ПОГ
    слоти_пулу = {}
    for сл, пул in (кандидати or {}).items():
        for r in пул:
            слоти_пулу.setdefault(str(r.get("id")), set()).add(сл)
    верхні = _ПОГ.пальта_пулу(кандидати)

    def _речі(іди):
        """Розгорнути ід у речі зі словника образу, з підставленим слотом.

        Частина комплекту дістає СВІЙ слот замість «комплект» (і поле
        `частина_комплекту`): структуру образу судять по слотах, і комплект,
        що лишився комплектом, закривав би одразу і верх, і низ."""
        вих = []
        for і in іди:
            з = словник.get(і) or {}
            r = dict(з, id=і, слот=(з.get("слот") or "?"))
            ч = (частини or {}).get(і)
            if ч and r.get("слот") == "комплект":
                r["слот"] = ч
                r["частина_комплекту"] = ч
            вих.append(r)
        return вих

    ід, дібрані, чому_ні = list(ід), [], None
    # Кроків — по одному на сімʼю блокера повноти плюс запас: більше дір, ніж
    # родин, у образі не буває, а нескінченного циклу тут бути не мусить.
    for _ in range(len(СЛОТИ_БЛОКЕРА) + 1):
        б = структура_образу(_речі(ід), слоти_пулу, сценарій, верхні=верхні)
        if not б:
            break
        коди = [_код_блокера(x) for x in б]
        ціль = next((к for к in коди if к in СЛОТИ_БЛОКЕРА), None)
        if ціль is None:
            # «два взуття» — це не діра, це інший образ; доклавши річ, її не
            # закрити, і вдавати протилежне код не буде («нема верху й низу»
            # тут більше не буває — вона своя ціль, СЛОТИ_БЛОКЕРА нижче).
            чому_ні = "blocker_not_closable_by_item=%s" % ",".join(str(к) for к in коди[:2])
            break
        взято = None
        for слот in СЛОТИ_БЛОКЕРА[ціль]:
            _пул = верхні if ціль == "нема_верхнього_шару" else (кандидати.get(слот) or [])
            for r in _пул[:_РЕЄСТР.C["добір_кандидатів"]]:
                і = r.get("id")
                if not і or і in ід:
                    continue
                словник.setdefault(і, dict(r, слот=(r.get("слот") or слот)))
                нові = структура_образу(_речі(ід + [і]), слоти_пулу, сценарій, верхні=верхні)
                # МЕНШЕ БЛОКЕРІВ І ЖОДНОГО НОВОГО: річ, що закриває «нема сумки»
                # й відкриває «у слоті «сумка» 2 речі», — не ремонт, а обмін.
                # І ЖОДНОГО ШАРУ, ЩО НЕ НАЛІЗЕ (рядок 158): приталене пальто поверх
                # обʼємного светра закриває слот, а вдягнути його не можна.
                if len(нові) < len(б) and not (
                        {_код_блокера(x) for x in нові} - set(коди)) and not _не_налізе(
                        _речі(ід + [і]), _речі(ід)):
                    взято = (і, слот)
                    break
            if взято:
                break
        # ── ОСНОВА БЕЗ ЖОДНОЇ ПОЛОВИНИ — ЄДИНИЙ ВИНЯТОК ІЗ «ОДНА РІЧ ЗА КРОК» ──
        # (рядок 46 дошки, власник 19.09). Коли бракує і верху, і низу РАЗОМ,
        # жоден одинокий кандидат не закриває блокер: рядок лишається тим самим
        # кодом («нема «низ» (і нема сукні…)» замість «нема «верх» і «низ»…»),
        # тобто лічба блокерів НЕ падає, і цикл вище відкидає кожного одинокого
        # кандидата як «нічого не змінив». Це не стосується часткової відсутності
        # (лишень верх або лишень низ) — там одна річ закриває блокер сама, і
        # генеральний цикл вище вже це знаходить. Тут — єдине місце в добірці, де
        # крок додає дві речі одразу, бо нарізно жодна ремонту не завершує.
        if взято is None and ціль == "нема_верху_низу":
            _в = next((r for r in (кандидати.get("верх") or [])[:_РЕЄСТР.C["добір_кандидатів"]]
                       if r.get("id") and r.get("id") not in ід), None)
            _н = next((r for r in (кандидати.get("низ") or [])[:_РЕЄСТР.C["добір_кандидатів"]]
                       if r.get("id") and r.get("id") not in ід), None)
            if _в and _н:
                словник.setdefault(_в["id"], dict(_в, слот=(_в.get("слот") or "верх")))
                словник.setdefault(_н["id"], dict(_н, слот=(_н.get("слот") or "низ")))
                нові = структура_образу(_речі(ід + [_в["id"], _н["id"]]), слоти_пулу, сценарій,
                                        верхні=верхні)
                if len(нові) < len(б) and not (
                        {_код_блокера(x) for x in нові} - set(коди)):
                    ід += [_в["id"], _н["id"]]
                    дібрані += [dict(id=_в["id"], слот="верх", чому=_ЧОМУ_БЛОКЕРА[ціль],
                                    напис=_ВМ.повідомлення("item_source", _ВМ.заява("item_added_by_code"))),
                                dict(id=_н["id"], слот="низ", чому=_ЧОМУ_БЛОКЕРА[ціль],
                                    напис=_ВМ.повідомлення("item_source", _ВМ.заява("item_added_by_code")))]
                    continue
        if взято is None:
            # ВМ-3а (рядок 224): ціль — кодом `missing_part` («нема_верху_низу» → no_base)
            чому_ні = "no_candidate:%s" % _ВМ.код_або_невідомо("missing_part", ціль)
            break
        і, слот = взято
        ід.append(і)
        дібрані.append(dict(id=і, слот=слот, чому=_ЧОМУ_БЛОКЕРА[ціль],
                            напис=_ВМ.повідомлення("item_source", _ВМ.заява("item_added_by_code"))))
    else:
        чому_ні = "structure_not_closed · steps=%d" % (len(СЛОТИ_БЛОКЕРА) + 1)
    if чому_ні or not дібрані or структура_образу(_речі(ід), слоти_пулу, сценарій, верхні=верхні):
        return list(ід[:len(ід) - len(дібрані)]), [], (чому_ні or "nothing_to_add")
    return ід, дібрані, None


