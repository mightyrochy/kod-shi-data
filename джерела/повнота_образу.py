    знайдені, невірні, частини = [], [], {}
    for x in (о.get("речі") or []):
        з, н, ч = _розпізнати_речі(str(x), словник, за_ном)
        знайдені += [і for і in з if і not in знайдені]
        невірні += н
        частини.update(ч)
    запис = _запис_образу(знайдені, невірні, словник, "поле «речі» вердикту", частини)
    ід = list(запис["ід"])
