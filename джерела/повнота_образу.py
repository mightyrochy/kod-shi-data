def _рядок_дібраних(дібрані, сценарій):
    """Рядок картки про речі, які доклав код у порожні слоти (ярус 3; виніс рядок 202 —
    той самий текст потрібен ярусу 4, коли діру закриває добір над варіантом)."""
    фраза = " і ".join(_ЧОГО_БРАКУЄ_СЛОВОМ.get(d["слот"], str(d["слот"]).replace("_", " "))
                       for d in дібрані)
    рядок_добору = ("%s%s до цього образу дібрав код, а не стилістка. Стилістка лишила %s, "
                    "а без %s образ не готовий."
                    % (фраза[:1].upper(), фраза[1:],
                       "це місце порожнім" if len(дібрані) == 1 else "ці місця порожніми",
                       "нього" if len(дібрані) == 1 else "них"))
    # ЧОМУ САМЕ ПАЛЬТО — СЛОВАМИ ПОГОДИ (рядок 146): «образ не готовий» без
    # причини читається як примха коду; умова дня — її ж вхід.
    import суд_погода as _ПОГ
    _т, _о = (сценарій or {}).get("темп_c"), (сценарій or {}).get("опади")
