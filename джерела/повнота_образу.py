# ── K-VAR-01 МІЖ КАРТКАМИ, А НЕ ЛИШЕ ВСЕРЕДИНІ РУКИ (рядок 48, 19.09.2026) ───
# `різноманітність()` нижче судить 10 варіантів ОДНІЄЇ руки — картки рук 1 і 2
# складаються в РІЗНИХ вердиктах, які одне одного не бачать за побудовою, тож
# «той самий клатч у двох картках одного прогону» K-VAR-01 не міг спіймати
# НІКОЛИ, скільки завгодно образів руки не давай. Виміряно `проби/сумка_руки.py`
# на каталог_повний (побачення·ресторан·19:00·20 °C, сіди 4242/17/101): пул
# сумок після відсічень — лише 22–23 моделі (взуття для порівняння — 29–37 із
# 1966), перетин пулів рук 1↔2 — 75–85 % усього слота. PR #92 дав руці 2
# ВЛАСНИЙ сід лише для розв'язання нічиєї (`bridge._сід_руки`) — це міняє
# ПОРЯДОК рівних, а не саму множину: коли реальний найкращий кандидат один на
# всю тонку множину, обидві моделі незалежно тягнуться до нього, хоч і бачать
# його в різному місці списку. Ліки тут не в порядку показу, а в тому, щоб
# повтор між картками СТАВ ВИДИМИЙ — той самий регістр, що для повтору
# всередині руки.
def повтор_прогону(реєстр, рука, речі):
    """Знахідка K-VAR-01, коли РІЧ цієї руки вже стояла в ІНШІЙ руці прогону.

    `реєстр` — {сім'я слота: [(рука, id, назва)]}, спільний на ВЕСЬ прогін (той
    самий сід): викликач (`bridge.від_моделі`) тримає його між викликами різних
    рук і передає сюди тим самим об'єктом — функція дописує в нього ЦЮ руку.
    Повертає ЩОНАЙБІЛЬШЕ одну знахідку (перший повтор), як і належить одному
    правилу на один рядок (Н-P37).

    `речі` — СКЛАД КАРТКИ цієї руки, а не все, що вона перебрала (рядок 70).
    ОДНА РУКА ТРИМАЄ В РЕЄСТРІ ОДНУ КАРТКУ: кожен виклик знімає з реєстру
    попередній запис ЦІЄЇ руки й кладе новий. Доти рука дописувала до реєстру
    верхній рівень КОЖНОГО виклику — останній із десяти варіантів ітерації 1,
    останній із п'яти ітерації 2, аж потім обраний образ, — і правило судило
    те, що промайнуло, хоч його знахідка й рядок діагнозу кажуть «та сама річ
    у двох КАРТКАХ». Виміряно `проби/povtor_remont_70.py` на сідах стенда 7 і
    11: повторена сумка («NEW YORK BAG хакі», «Rio») стояла в руці 1 в образі
    о10 ітерації 1, а в руці 2 — в о5 ітерації 2; на картки рук 1 і 2 при тому
    йшли РІЗНІ сумки на обох сідах. Тобто знахідка була правдива про перебір і
    хибна про картки, а власниця читала в діагнозі саме про картки.
    ЩО ПРАВИЛО НЕ ВТРАЧАЄ: коли дві руки справді винесуть на картку ту саму
    річ, останні записи обох рук у реєстрі — це саме ті картки, і повтор так
    само називається. Реєстр і далі наповнюють сусідні руки паралельно, тож
    рука, яка складає картку першою, судиться проти того, що інша має НА ТОЙ
    МОМЕНТ, — це та сама межа, що й була (`показ.html`: «в момент складання
    іншої руки ще може не бути»)."""
    import реєстр_правил as _РЕЄСТР
    for сім in list(реєстр):
        реєстр[сім] = [з for з in реєстр[сім] if з[0] != рука]
    знайдено = None
    for r in (речі or []):
        сім = _сім_я_слота(r.get("слот"), r.get("назва"))
        бачені = реєстр.setdefault(сім, [])
        інша_рука = next((р2 for р2, і2, _ in бачені if р2 != рука and і2 == r.get("id")), None)
        if інша_рука and знайдено is None:
            знайдено = (r, інша_рука)
        бачені.append((рука, r.get("id"), r.get("назва")))
    if not знайдено:
        return None
    r, інша_рука = знайдено
    return _РЕЄСТР._зн(
        "K-VAR-01", "soft",
        "«%s» уже стоїть у руці %s цього прогону — та сама річ, а не вибір"
        % (r.get("назва") or r.get("id"), інша_рука),
        [r.get("id")],
        "тема-4 XIII: набір існує, щоб було з чого обирати; та сама річ у двох "
        "картках одного прогону — це повтор, не вибір ші",
        ремонт="узяти в цій руці іншу річ тієї самої сім'ї слота",
    )


def _слоти_повноти(образи, кандидати):
    """{слот: [ід образів]} і {ід образу: [причини]} — чого бракує за блокерами.

    ЧОМУ ЦЕ ІСНУЄ (18.09.2026, спіймано власницею на опублікованому продукті).
    Вітрина бралась ЛИШЕ з вузлів напруги, а «нема сумки» вузлом не буває: слот
    порожній не має ребер, за якими напруга рахується. Тож ремонт другої ітерації
    фізично не міг полагодити те, через що вибір потім відмовляв, — у контексті
    моделі не було жодної сумки, а пулу першого пакета вона вже не бачить.
    Третя річ така сама: сімʼя слотів велика, а показували з неї нуль."""
    import реєстр_правил as _РЕЄСТР
    слоти, чому = {}, {}
    for і, о in enumerate(образи or [], 1):
        ід = str(о.get("номер") or о.get("ід") or ("о%d" % і))
        коди = []
        # ЗАПИС `bridge._запис` тримає блокери полем, вердикт (`ВЕРДИКТ_V1`) — у
        # «структура»: одна функція читає обидві форми, бо кличуть її з обох боків.
        for b in (о.get("блокери") or (о.get("структура") or {}).get("блокери") or []):
            к = str((b or {}).get("код") or "")
            if к in СЛОТИ_БЛОКЕРА and к not in коди:
                коди.append(к)
        for к in коди:
            чому.setdefault(ід, []).append(_ЧОМУ_БЛОКЕРА[к])
            _сім = [с for с in СЛОТИ_БЛОКЕРА[к] if (кандидати or {}).get(с)]
            # СІМʼЯ «ТРЕТЬОЇ РЕЧІ» ЗРІЗАЄТЬСЯ ДО НАЙБАГАТШИХ СЛОТІВ: потрібна ОДНА
            # річ, а слотів у сімʼї одинадцять — платити за всі означало б платити
            # за вибір, якого не просили.
            if len(_сім) > 1:
                _сім = sorted(_сім, key=lambda с: -len(кандидати[с]))[:_РЕЄСТР.C["слотів_третьої"]]
            for с in _сім:
                if ід not in слоти.setdefault(с, []):
                    слоти[с].append(ід)
    return слоти, чому


def _вітрина_ремонту(образи, кандидати, скільки_слотів=2, на_слот=12):
    """Речі, якими можна розвʼязати те, що тисне — саме в тих слотах, де тисне.
    → (`вітрина` за схемою `ВЕРДИКТ_V1.вітрина`: {слот: [річ]}, ноти для `завдання.вимоги`).

    ЧОМУ ЦЕ ІСНУЄ (31.08.2026). Промпт ремонту ніс лише ВЛАСНІ образи моделі:
    зміряно — 2 094 символи, 5 id, нуль кандидатів, нуль слотів. А кожен виклик іде
    свіжим контекстом без історії, тож на другій ітерації модель фізично не бачила
    жодної речі, крім тих, які сама вже обрала. Якщо ремонт вимагав ІНШОГО взуття,
    взуття не було звідки взяти — вона могла лише переставляти вже обране.
    Приймальня при цьому існувала: `ід_з_тексту` резолвить річ поза пулом із повного
    каталогу. Тобто приймальня була, вітрини не було.

    ЧОМУ НЕ ВЕСЬ ПУЛ. Повторити сотні речей у кожному виклику ремонту означало б
    платити за них удруге й утретє. Вітрина адресна: спершу слоти, яких вимагають
    СТРУКТУРНІ БЛОКЕРИ образів (нема сумки, нема взуття, нема третьої речі —
    `_слоти_повноти`), а вже потім ВУЗЛИ напруги — з того, що код зміряв на тому,
    що ші справді склала, а не з припущення. Речі, які модель уже взяла, виключаються: показувати їй те,
    що вона й так має, — не вибір.

    ОБʼЄКТОМ, А НЕ РЯДКАМИ (Т-03). Річ вітрини — той самий `_річ_пулу`, що будує
    пул першого пакета: один будівник речі на обидва виклики, інакше вітрина
    розійшлася б із пулом на першій же правці полів. Знайдене на «потрібно» моделі
    (`за_запитом`) стоїть у вітрині свого слота ЗАВЖДИ, а не лише коли слот —
    вузол: це відповідь на її запит, і без неї право на річ поза пулом порожнє.
    """
    if not образи or not кандидати:
        return {}, []
    import collections as _c, реєстр_правил as _РЕЄСТР
    вузли = _c.Counter(о.get("вузол") for о in образи if о.get("вузол") in кандидати)
    взяті = {i for о in образи for i in (о.get("ід") or [])}
    # НОМЕРИ — З ПОВНОГО ПУЛУ, як їх бачила модель у першій ітерації і як їх
    # читає `ід_з_тексту`. Підмножина, пронумерована сама по собі, — інша нумерація.
    _ном = номери_речей(кандидати)[0] if ПАКУВАТИ_ІНДЕКСОМ else {}
    вітрина, ноти = {}, []
    # ── ПАЛЬТОВА ЗОНА (рядок 146): коли образу бракує верхнього шару в холод, слот
    # вітрини — лише речі, що в образі ним справді стануть, теплі першими
    # (`суд_погода.пальта_пулу`). Піджак з основним слотом «верх», показаний першим,
    # модель узяла б — а блокера він не закриває, і обидві спроби згоріли б на ньому.
    _коди = {str((b or {}).get("код") or "") for о in образи
             for b in (о.get("блокери") or (о.get("структура") or {}).get("блокери") or [])}
    _джерело = {}
    if "нема_верхнього_шару" in _коди:
        import суд_погода as _ПОГ
        _джерело["верхній_шар"] = _ПОГ.пальта_пулу(кандидати)

    def _вільні(слот, скільки):
        """Речі слота, яких модель не брала, по одній на МОДЕЛЬ (`group_id`).
        Дедуп навмисно: вісім кольорів однієї сумки — це один вибір, повторений
        вісім разів, і за нього платить кожен виклик ремонту."""
        вих, моделі = [], set()
        for r in (_джерело[слот] if слот in _джерело else (кандидати.get(слот) or [])):
            if r.get("id") in взяті or r.get("за_запитом"):
                continue
            м = r.get("group_id") or r.get("id")
            if м in моделі:
                continue
            моделі.add(м); вих.append(_річ_пулу(r, _ном))
            if len(вих) >= скільки:
                break
        return вих

    # ── СПЕРШУ ТЕ, ЧОГО ВИМАГАЄ БЛОКЕР, І ЛИШЕ ПОТІМ ВУЗОЛ НАПРУГИ (18.09.2026) ──
    # Порядок не косметичний: вузол напруги — це «тут вузько», а блокер структури —
    # «цього образу не покажуть узагалі». Друге сильніше за перше, і коли на слоти
    # бракує бюджету, платити треба за те, без чого картки не буде.
    _треба, _чому_образів = _слоти_повноти(образи, кандидати)
    for слот in _треба:
        речі = _вільні(слот, _РЕЄСТР.C["вітрина_блокера"])
        if речі:
            вітрина[слот] = речі
    if _чому_образів:
        # НОТА АДРЕСНА: до правки вітрина мовчала про те, ЧИЙ образ неповний, і
        # модель ремонтувала не те. Групуємо за причиною, щоб рядок лишався коротким.
        # Повнота — умова показу, не порада: неповного образу код жінці не покаже.
        за_причиною = {}
        for ід, причини in _чому_образів.items():
            за_причиною.setdefault(" / ".join(причини), []).append(ід)
        ноти.append(нота_повноти("; ".join("%s — %s" % (", ".join(sorted(ід)), причина)
                                           for причина, ід in sorted(за_причиною.items()))))
    for слот, скільки in вузли.most_common(скільки_слотів):
        if слот in вітрина:
            continue
        речі = _вільні(слот, на_слот)
        if речі:
            вітрина[слот] = речі
    for слот, пул in кандидати.items():
        for r in пул:
            if r.get("за_запитом") and r.get("id") not in взяті:
                вітрина.setdefault(слот, []).append(
                    dict(_річ_пулу(r, _ном), за_запитом=str(r["за_запитом"])))
    if вітрина:
        ноти.append(НОТА_ВІТРИНИ)
    # ── ДЕ МОЖНА ЛАМАТИ — З РЕАЛЬНИХ ОБРАЗІВ, А НЕ З ВИГАДАНИХ ─────────────
    # Слот розриву доти обирався в композиторі за 200 ВИГАДАНИХ комбінацій із
    # топ-5 на слот: образів, яких ніхто не збирав і не збиратиме. Після першої
    # ітерації на руках десять СПРАВЖНІХ образів, кожен уже проведений крізь граф
    # із вузлом напруги. Міряти по них і дешевше, і чесніше — той самий принцип,
    # яким прибрано власний образ коду: код судить складене, не вигадане.
    # МЕЖА ЛИШАЄТЬСЯ ТА САМА, що стерегла композитор: ламати можна лише далеко від
    # обличчя. Верх, сукня й верхній шар не пропонуються ніколи — там колір біля
    # обличчя вирішує (K-CLR-02), і розрив коштував би головного правила системи.
    _далеко = [(с, n) for с, n in вузли.most_common()
               if с not in ("верх", "сукня", "комплект", "верхній_шар")]
    if _далеко:
        # слот — вузол напруги в найбільшій кількості образів і далеко від обличчя, тож
        # колірні правила біля обличчя тут не діють; оголошений розрив судиться мʼякше
        ноти.append(нота_розриву(_далеко[0][0]))
    return вітрина, ноти


