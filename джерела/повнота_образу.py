def _без_вказівки_моделі(суть):
    """Суть блокера без слів, адресованих МОДЕЛІ. Те, що лишилось, — про образ."""
    т = _ВКАЗІВКА_МОДЕЛІ.sub("", str(суть or ""))
    т = _СВІДОМО_СЛОВОМ.sub("", т)
    for шаб, чим in _SKU_ЖІНЦІ:
        т = шаб.sub(чим, т)
    return _re_вк.sub(r"\s{2,}", " ", т).strip(" ,;:")


def _дописати(повідомлення, заяви):
    """Дописати заяви до повідомлення картки «чого в образі нема» (`card_incomplete`), або
    зібрати нове, коли його ще не було. Ч-1 (п.12): доти тут склеювались рядки через пробіл —
    тепер склеюються ЗАЯВИ, а речення з них складає мовна модель."""
    з = [x for x in (заяви or []) if x]
    if not з:
        return повідомлення
    було = list((повідомлення or {}).get("statements") or [])
    return _ВМ.повідомлення("card_incomplete", *(було + з))


