def _бракує_адресно(образи, потрібні, вітрина, чому):
    """Рядки «о1 — ти повернула …, слота «сумка» в цьому нема; закривають: …».

    ОДИН РЯДОК НА ОБРАЗ І ТРИ РЕЧІ НА СЛОТ: уся вітрина вже стоїть у промпті
    полем, і переказувати її вдруге означало б платити за неї двічі. Три —
    щоб «закривають» лишалось прикладом, а не новим вибором.
    """
    за_образом = {}
    for слот, іди in (потрібні or {}).items():
        for ід in іди:
            за_образом.setdefault(str(ід), []).append(слот)
    рядки = []
    for о in образи:
        ід = str(о.get("ід") or "")
        слоти = за_образом.get(ід) or []
        if not слоти:
            continue
        речі = ", ".join(str(x) for x in (о.get("речі") or [])[:8]) or "—"
        закр = "; ".join(
            "«%s» закривають %s" % (с, ", ".join(
                "%s %s" % (r.get("н"), r.get("назва")) for r in ((вітрина.get(с) or [])[:3])))
            for с in слоти if (вітрина.get(с) or []))
        рядки.append("%s — ти повернула %s, і цього мало: %s. %s"
                     % (ід, речі, " / ".join(чому.get(ід) or слоти),
                        закр or "у вітрині цього слота нема"))
    return рядки


def вердикт_повноти(вердикт, спроба=1):
    """Той самий вердикт ітерації 2, звужений до одного завдання: доповнити до повного.

    `спроба` — котрий це виклик ремонту повноти на цю руку (1 або 2). Друга несе
    `ВИМОГИ_ПОВНОТИ_2` і адресний перелік `бракує`: перше прохання ші вже чула.

    None, коли доповнювати нема чого (усі образи повні) або нема чим (вітрина не
    несе жодного слота, якого бракує) — тоді й зайвого виклику до моделі нема.
    """
    в = dict(вердикт or {})
    образи = [о for о in (в.get("образи") or [])
              if isinstance(о, dict) and any(
                  str((b or {}).get("код") or "") in СЛОТИ_БЛОКЕРА
                  for b in ((о.get("структура") or {}).get("блокери") or []))]
    вітрина = в.get("вітрина") or {}
    if not образи or not вітрина:
        return None
    # ОБРАЗ БЕЗ ГЕЙТІВ — ПЕРШИМ (рядок 146): модель доповнює ОДИН, і коли перший у
    # переліку ще й несе гейт (річчю він не лікується), ремонт закінчується образом,
    # якого код однаково не прийме. Виміряно на «+5, дощ», сід 3, рука 2: п'ять
    # образів без пальта, перший — із K-PAL-03, а образ без гейта губився.
    образи.sort(key=lambda о: 1 if _чому_не_можна(dict(о, структура=dict(ок=True, блокери=[])))
                else 0)
    потрібні, чому = _слоти_повноти(образи, вітрина)
    if not потрібні:
        return None
    # ОБРАЗ ТУТ — САМА СТРУКТУРА: знахідки, чекліст і вузол напруги до питання
    # «чого бракує» стосунку не мають, а важать більшу частину промпта ремонту.
    в["образи"] = [{k: v for k, v in о.items() if k in ("ід", "підпис", "речі", "структура")}
                   for о in образи]
    for ключ in ("набір", "мова", "реєстр"):
        в.pop(ключ, None)
    # ВІТРИНА ЗВУЖУЄТЬСЯ ДО СЛОТІВ ПОВНОТИ: вузли напруги тут не питання, а зайвий
    # виклик має бути найдешевшим із тих, що працюють.
    в["вітрина"] = {с: р for с, р in вітрина.items() if с in потрібні}
    завдання = dict(в.get("завдання") or {})
    завдання["образів"] = 1
    завдання["відповідь"] = "ОБРАЗИ_V1"
    if int(спроба or 1) >= 2:
        # АДРЕСНО — ОКРЕМИМ ПОЛЕМ, А НЕ ХВОСТОМ ВИМОГИ: рядок «бракує» довгий
        # (склад образу + речі вітрини), і всередині `вимоги` він губився б між
        # чотирма короткими наказами, які мусять читатись як наказ.
        завдання["вимоги"] = list(ВИМОГИ_ПОВНОТИ_2)
        в["бракує"] = _бракує_адресно(в["образи"], потрібні, в["вітрина"], чому)
    else:
        завдання["вимоги"] = list(ВИМОГИ_ПОВНОТИ) + [
            "Адресно: " + "; ".join("%s — %s" % (ід, " / ".join(п))
                                    for ід, п in sorted(чому.items()))]
    в["завдання"] = завдання
    return в


# ── ВИБІР, ЯКИЙ ВИДНО Й БЕЗ «обрано» (рядок 208, З-6) ────────────────────────
# Слабка модель відповідає на ВИБІР_V1 не тим ключем («відповідь»: «о1»), чужим
# записом ід («O1» латиницею, «образ 3», просто 3) або самим образом замість вибору
# ({ід: «образ_1», речі: […]}). Доти кожне з цього — «відповідь не прочитано»,
# повторний виклик, а слабка модель на повторі робить те саме, і рука падала в
# запасний образ коду, хоч модель СВІЙ вибір назвала. Тепер вибір читається, коли
# він ОДНОЗНАЧНИЙ: ід образу вердикта стоїть у рівно одному полі-кандидаті, або склад
# відповіді-образу рівно дорівнює складу одного образу вердикта. Ехо вхідного
# ВЕРДИКТ_V1 назад (З-6) вибором не є: його поля — поля вердикта, і їх не читаємо.
_НЕ_ВИБІР = frozenset(set(_ПР.ВИБІР_V1["поля"]) | set(_ПР.ВЕРДИКТ_V1["поля"])
                      | set(_ПР.ОБРАЗ_МОДЕЛІ["поля"])) - {"обрано", "ід"}
# Поля, які має лише ВЕРДИКТ: відповідь із ними — ехо входу, навіть коли обрив лишив
# у ній рівно один цілий образ (без цього обрізане ехо «обирало» перший образ).
# Перелік живе в протоколі (Т-7): той самий, яким розбір ОБРАЗИ_V1 знімає ехо ремонту,
# і з ним — список суду `вердикт` у формі на дроті (`протокол.поля_входу`).


def _ід_значенням(ключ, v, ідентифікатори):
    """Значення поля відповіді → ід образу вердикта, який воно однозначно називає.

    Число приймається лише в `обрано` (3 → «о3»): у будь-якому іншому полі воно
    може бути чим завгодно — «ітерація»: 2 у вердикті, переписаному назад."""
    if isinstance(v, (list, tuple)) and len(v) == 1:
        v = v[0]
    if isinstance(v, bool) or not isinstance(v, (str, int)) or (isinstance(v, int) and ключ != "обрано"):
        return None
    с = _re.sub(r"[\s#№«»\"'_\-.:]", "", str(v).strip().lower().replace("o", "о"))
    if с in ідентифікатори:
        return с
    м = _re.fullmatch(r"(?:о|образ|варіант)?(\d+)", с)
    return ("о" + м.group(1)) if м and ("о" + м.group(1)) in ідентифікатори else None


def _обрано_однозначно(об, вердикт, словник, за_ном):
    """→ (образ вердикта, як прочитано) або (None, None).

    Відповідь-ОБРАЗ судиться лише складом: її власне «ід» («образ_1») — імʼя, яке
    модель дала сама, і нумерація вердикта з ним не мусить збігатись."""
    if _ПР.поля_входу(об):
        return None, None
    образи = [о for о in ((вердикт or {}).get("образи") or []) if isinstance(о, dict)]
    за_ід = {str(о.get("ід") or ""): о for о in образи}
    речі = об.get("речі")
    if речі is None and isinstance(об.get("образи"), list) and len(об["образи"]) == 1 \
            and isinstance(об["образи"][0], dict):
        речі = об["образи"][0].get("речі")
    # Т-7: образ на дроті стоїть у «твій_образ» — «сам образ замість вибору» від
    # моделі, що бачила таку форму, приходить у тій самій обгортці
    if речі is None and isinstance(об.get(_ПР.ТВІЙ_ОБРАЗ), dict):
        речі = об[_ПР.ТВІЙ_ОБРАЗ].get("речі")
    if речі is not None:
        свій = set()
        for x in _список(речі):
            з, _н, _ч = _розпізнати_речі(str(x), словник, за_ном, поле=True)
            свій |= {і for і in з if і in словник}
        збіги = [о for о in образи if свій and set(_склад_вибору(о, словник, за_ном)["ід"]) == свій]
        if len(збіги) == 1:
            return збіги[0], ("вибір прочитано за складом: відповідь — сам образ, і його речі — "
                              "рівно речі «%s»" % збіги[0].get("ід"))
        return None, None
    знайдено = {}
    for к, v in об.items():
        if к in _НЕ_ВИБІР:
            continue
        ід = _ід_значенням(к, v, за_ід)
        if ід:
            знайдено.setdefault(ід, к)
    if len(знайдено) == 1:
        ід, к = next(iter(знайдено.items()))
        return за_ід[ід], "«обрано» прочитано з поля «%s»: «%s» → «%s»" % (к, об.get(к), ід)
    return None, None


