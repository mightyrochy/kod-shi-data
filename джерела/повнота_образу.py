# СТЕЛЯ ПЕРЕБОРУ ЯРУСУ 4 — У РЕЧАХ, ЯКІ СУДИТЬ СУДДЯ (рядок 202, знахідка виконавиці рядка 208,
# 24.09). Ціна перебору — не число варіантів, а речі в них: суддя міряє кожну. На
