_БЛОКЕРІВ_НА_КАРТЦІ = 3        # п.9: групувати до трьох тем, а не висипати всі
_РЕ_СІМ_Я = _re_вк.compile(r"у сім'ї «([^»]+)»")
# ДРУГЕ «ОБРАЗ НЕПОВНИЙ» ПОСЕРЕД РЕЧЕННЯ (рядок 210, 25.09.2026). Рядок картки
# починається з «Образ неповний: », а один блокер (`суд_від_моделі`: «образ
# неповний: 3 речі, а для нагоди потрібно щонайменше 4») несе ту саму шапку в
