# Перелічувались саме РЕЧІ: по 8–12 назв на кожну сім'ю, до 40 символів кожна.
# ЩО ТЕПЕР. Жінці — одне-два зрозумілі речення: ЩО не так (згруповано за видом
# блокера, не за річчю) і ЩО зробити. Назв речей на картці нема: слот назвати
# корисно («по кілька речей на взуття й сумку» — це дія), назвати дванадцять
# черевиків — ні. Повний перелік не гине: він іде в `чому`, тобто у звіт власника
