def обхід(вузол, шлях, біда, вузлів):
    """Кожен вузол усіх шести схем: тип відомий, `треба` ⊆ `поля`, елемент є.

    Без цього `треба=("образв",)` з друкарською помилкою давало б вічну «помилку
    формату» на валідній відповіді моделі — і винною виглядала б модель. Мовчить,
    поки все добре: сто зелених рядків про вузли ховають решту проби.
    """
    вузлів.append(шлях)
    if вузол.get("тип") not in P.ТИПИ:
        біда.append("%s: невідомий тип «%s»" % (шлях, вузол.get("тип"))); return
    if вузол["тип"] == "обʼєкт":
        зайві = set(вузол["треба"]) - set(вузол["поля"])
        if зайві:
            біда.append("%s: у «треба» є неоголошені поля %s" % (шлях, sorted(зайві)))
        for k, в in вузол["поля"].items():
            обхід(в, "%s.%s" % (шлях, k), біда, вузлів)
    elif вузол["тип"] == "список":
        if "елемент" not in вузол:
            біда.append("%s: список без «елемент»" % шлях); return
        обхід(вузол["елемент"], шлях + "[]", біда, вузлів)
    elif вузол["тип"] == "карта":
        if "по_ключу" not in вузол:
            біда.append("%s: карта без «по_ключу»" % шлях); return
        обхід(вузол["по_ключу"], шлях + ".*", біда, вузлів)


біда, вузлів = [], []
