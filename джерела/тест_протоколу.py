звірка("фікстура на кожну з шести схем", {ім_схеми(f) for f in файли} == set(P.СХЕМИ),
       str(sorted(ім_схеми(f) for f in файли)))
for f in файли:
    пом = P.перевірити(P.СХЕМИ[ім_схеми(f)], json.load(open(f, encoding="utf-8")))
