def звірка(що, умова, деталі=""):
    print(("  ✓ " if умова else "  ✗ ") + що + (("  " + деталі) if деталі and not умова else ""))
    if not умова:
        провали.append(що)


def ім_схеми(шлях):
    """Ім'я схеми з імені файлу — те саме правило, що в приймальній команді Т-01."""
    return os.path.basename(шлях).split(".")[0]


