#   приглушені 5 ≤ C ≤ 32 — вікна приглушених слів (хакі 35–70/8–32,
#                     петроль 12–55/8–32, тауп 29–88/5–23, какао 25–63/13–27).
# НИЖНЯ МЕЖА ХРОМИ в обох — 5 (тауп і пудровий), і вона не косметична: без неї
# «приглушені» брали ахроматику й тримали 8 671 річ каталогу з 11 829 (73 %), бо
# чорне, сіре й біле формально теж «не гучні». Жодна жінка не зве чорну сукню
# приглушеним кольором; слово жінки — про приглушену БАРВУ, і межа стоїть там, де
# барва кінчається. Виміряно на каталог_повний (11 829 речей): «приглушені»
# 8 671 → 3 346 (73.3 % → 28.3 %), «пастельні» 3 068 → 1 045 (25.9 % → 8.8 %).
ПОРІГ_ТЕМНІ_L, ПОРІГ_СВІТЛІ_L = 45.0, 70.0
ПОРІГ_ПАСТЕЛЬ_L, ПОРІГ_БАРВИ_C, ПОРІГ_ПАСТЕЛЬ_C, ПОРІГ_ПРИГЛУШЕНІ_C = 65.0, 5.0, 40.0, 32.0
КЛАСИ_КОЛЬОРУ = {
    "темні":      (0.0, ПОРІГ_ТЕМНІ_L, 0.0, 200.0),
    "світлі":     (ПОРІГ_СВІТЛІ_L, 100.0, 0.0, 200.0),
    "яскраві":    (0.0, 100.0, C["hi_C"], 200.0),
    "пастельні":  (ПОРІГ_ПАСТЕЛЬ_L, 100.0, ПОРІГ_БАРВИ_C, ПОРІГ_ПАСТЕЛЬ_C),
    "приглушені": (0.0, 100.0, ПОРІГ_БАРВИ_C, ПОРІГ_ПРИГЛУШЕНІ_C),
}
# Слово жінки чи моделі → ключ класу. Хвости («кольори», «відтінки», «тони»,
# «гами») відкидаються, бо клас несе прикметник, а не іменник при ньому.
_СИНОНІМ_КЛАСУ = {"темн": "темні", "чорнот": "темні", "світл": "світлі", "яскрав": "яскраві",
                  "неон": "яскраві", "кислотн": "яскраві", "пастел": "пастельні", "ніжн": "пастельні",
                  "приглушен": "приглушені", "притлумлен": "приглушені", "спокійн": "приглушені"}
_ХВІСТ_КЛАСУ = re.compile(r"\b(кольор\w*|відтін\w*|тон\w*|гам\w*|барв\w*)\b", re.I)


def клас_кольору(слово):
    """Ключ класу кольору для слова вето («темні кольори» → «темні») або None.

    None означає «читача класу на це слово нема», і саме за цим показ вирішує, чи
    можна писати «Твої межі враховано». Слово лексикону («чорний») класом не є —
    його читає підрядковий пошук по назві кольору речі, як і доти."""
    т = _ХВІСТ_КЛАСУ.sub(" ", str(слово or "").lower())
    for w in re.findall(r"[a-zа-яіїєґ]{3,}", т):
        for основа, клас in _СИНОНІМ_КЛАСУ.items():
            if w.startswith(основа):
                return клас
    return None


def річ_у_класі(x, клас):
    """Чи колір речі (чи елемента) ВЕСЬ лежить у вікні класу: True / False / None.

    None — колірного входу нема зовсім (`межі_кольору` мовчить) або класу не знаємо:
    тоді річ не чіпають. True лише тоді, коли вікно речі ціле всередині вікна класу —
    вікно, що лежить по обидва боки порога, лишається в пулі (шапка секції)."""
    в = КЛАСИ_КОЛЬОРУ.get(клас)
    м = межі_кольору(x) if isinstance(x, dict) else None
    if в is None or м is None:
        return None
    return в[0] <= м[0] and м[1] <= в[1] and в[2] <= м[2] and м[3] <= в[3]
