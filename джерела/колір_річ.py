# ЩО ТУТ БУЛО. Річ із кольором зі слова стояла в суді центром вікна, і гучність
# (`гучність(lab)`) та сім'я (`сім_я(lab)`) рахувались з центру. Центр завищує хрому:
# «синій» — центр C* 46, виміри того самого слова — медіана 14–16; «зелений» 52 проти 22–26.
# Тож вікно «зелений» ставало гучним за побудовою, і K-ACC-01 писав витрату бюджету хроми
# там, де виміряні зелені речі каталогу гучними не є.
# ЩО СТАЛО. Гучність вікна — «так», коли все вікно хроми над `hi_C`, «ні» — коли все під
# ним, інакше «можливо»; сім'я вікна — та, яку дає КОЖНА точка вікна (сітка по L, C, тону),
# інакше None (невідомо). Вимір — як доти: точка дає «так»/«ні» і `сім_я(lab)`.
def гучність_меж(x, стеля=None):
    """«так» / «можливо» / «ні»: чи колір речі чи елемента гучний (C* ≥ `hi_C`, K-COL-02) за
    `межі_кольору`; None — кольору нема. Витрату бюджету правило рахує лише на «так»,
    «можливо» — запис «без входу» з полем `колір_не_вимір` (п.4).
    `стеля` — стеля гучності нагоди (K-KOH-08): гучність тоді — C*·L*/50 понад стелю; на
    вікні добуток росте з обома осями, тож межі — кути вікна (C0·L0, C1·L1)."""
    м = межі_кольору(x)
    if м is None:
        return None
    if стеля is not None:
        с = float(стеля)
        return "так" if м[2] * м[0] / 50.0 > с else "ні" if м[3] * м[1] / 50.0 <= с else "можливо"
    # вікно, що лише сягає порога (кемел, коричневий, хвойний… — C* до 40), — тихе слово: точка
    # рівно на порозі — межа вікна, а не річ, тож «ні», а не «можливо» (вимір на порозі — «так»)
    return "так" if м[2] >= C["hi_C"] else "ні" if м[3] <= C["hi_C"] else "можливо"


_СІТКА_ВІКНА = 5          # точок на вісь L і C; тон — через кожні ≤10° дуги


def _сім_я_вікна(в):
    """Сім'я, яку `сім_я` дає кожній точці сітки вікна (L, C, дуга), або None. Вікно, всі
    точки якого нейтралі різного роду (чорний: тепла / холодна / ахроматична за b*), —
    «нейтраль»: рід нейтралі тут не сім'я кольору."""
    import math as _м
    L0, L1, C0, C1, д = в
    if д is None:
        тони = list(range(0, 360, 10))
    else:
        ш = (д[1] - д[0]) % 360.0
        n = max(1, int(_м.ceil(ш / 10.0)))
        тони = [(д[0] + ш * i / n) % 360.0 for i in range(n + 1)]
    сім = set()
    for i in range(_СІТКА_ВІКНА):
        L = L0 + (L1 - L0) * i / (_СІТКА_ВІКНА - 1)
        for j in range(_СІТКА_ВІКНА):
            Cc = C0 + (C1 - C0) * j / (_СІТКА_ВІКНА - 1)
            for h in тони:
                сім.add(сім_я((L, Cc * _м.cos(_м.radians(h)), Cc * _м.sin(_м.radians(h)))))
    if len(сім) > 1 and all(с.startswith("нейтраль") for с in сім):
        return "нейтраль"
    return next(iter(сім)) if len(сім) == 1 else None


_СІМ_Я_ВІКНА = {}


def сім_я_меж(x):
    """Сім'я кольору речі чи елемента з меж: вимір — `сім_я(lab)`; вікно слова — сім'я, коли
    всі точки вікна лежать в одній (`FAMILIES` чи «нейтраль-…»), інакше None — невідомо;
    None і тоді, коли кольору нема. Вікон у лексиконі кілька десятків — кеш за вікном."""
    м = межі_кольору(x)
    if м is None:
        return None
    if не_вимір(x) is None:
        return сім_я(tuple(x["lab"]))
    if м not in _СІМ_Я_ВІКНА:
        _СІМ_Я_ВІКНА[м] = _сім_я_вікна(м)
    return _СІМ_Я_ВІКНА[м]


def _на_дузі(h, дуга):
    """Чи тон h лежить на дузі (lo, hi); дуга з переходом через 0° (lo > hi) — теж."""
    lo, hi = дуга
    return (lo <= h <= hi) if lo <= hi else (h >= lo or h <= hi)


def _кут(a, b):
    """Коротша кутова відстань між двома тонами, 0…180°."""
    d = abs(a - b) % 360.0
    return min(d, 360.0 - d)


def розкид_тону(a, b):
    """(мін, макс) кутової відстані тонів двох речей чи елементів.

    Два виміри — одне число двічі. Вікно — усе, що дозволяють його дуги: мінімум 0,
    коли дуги перетинаються, максимум 180, коли дуга однієї заходить навпроти
    другої; інакше обидва — на кінцях дуг (відстань між дугами кусково-лінійна).
    Ахроматичне слово тону не має — (0, 180). None — котрогось кольору нема."""
    ма, мб = межі_кольору(a), межі_кольору(b)
    return None if ма is None or мб is None else _розкид_дуг(ма[4], мб[4])


def _розкид_дуг(да, дб):
    """`розкид_тону` над двома дугами тону (CIELAB чи кола художника); None — без тону."""
    if да is None or дб is None:
        return (0.0, 180.0)
    кінці = [(x, y) for x in да for y in дб]
    перетин = any(_на_дузі(k, дб) for k in да) or any(_на_дузі(k, да) for k in дб)
    навпроти = ((дб[0] + 180.0) % 360.0, (дб[1] + 180.0) % 360.0)
    протилежні = any(_на_дузі(k, навпроти) for k in да) or any(_на_дузі(k, да) for k in навпроти)
    return (0.0 if перетин else min(_кут(x, y) for x, y in кінці),
            180.0 if протилежні else max(_кут(x, y) for x, y in кінці))


# ВІДЛУННЯ — ЗА КОЛОМ ХУДОЖНИКА (КОЛІР-Р2, рядок 2693; CLAUDE.md п.18). Повтор кольору
# (K-COMP-05 відлуння, K-ACC-01 опора, групи фокусів K-CRA-02, групи акцентів K-COL-05, голоси
# K-PAL-15) — це «той самий колір», тобто відношення тону, і судиться тим самим колом, що й
# схеми палітри (`colorspace.у_коло_художника`, K-COL-03 §4), а не кутом CIELAB. Доти дуга
# була 45° CIELAB, а це 21° кола в синіх і 61–83° у червоних і помаранчевих: червоний ×
# помаранч, бордо × мідь, лайм × смарагд (сусідні сектори, аналогова пара) були «одним
# голосом», а блакить × кобальт — ні. Межа — сектор 12-кольорового кола (крок 30°): два тони
# одного голосу, коли між ними на колі ≤ 15° (±15° — пів сектора). ДЕ ЛАМАЄТЬСЯ: коло між
# опорами `_КОЛО` — лінійна інтерполяція, не виміряне сприйняття; межа 15° — тверда, тож пара
# 14° і пара 16° судяться різно, хоч оком майже однакові.
ДУГА_ВІДЛУННЯ = 15.0


def кут_на_колі(h1, h2):
    """Коротша відстань двох тонів CIELAB на колі художника, 0…180°."""
    return _кут(у_коло_художника(h1), у_коло_художника(h2))


def _дуга_на_колі(м):
    """Дуга тону `межі_кольору` на колі художника. `у_коло_художника` зростає по всьому
    колу, тож дуга переходить у дугу — досить перенести її кінці. None — без тону."""
    return None if м is None or м[4] is None else tuple(у_коло_художника(h) for h in м[4])


def розкид_тону_на_колі(a, b):
    """`розкид_тону`, виміряний на колі художника (число для тексту знахідки; вердикт —
    `відношення`)."""
    ма, мб = межі_кольору(a), межі_кольору(b)
    return None if ма is None or мб is None else _розкид_дуг(_дуга_на_колі(ма), _дуга_на_колі(мб))


# ── ОДНЕ API ВІДНОШЕНЬ КОЛЬОРУ (КОЛІР-Р4, рядок 2694, хвиля 1; CLAUDE.md п.12, п.18) ──
# ЩО ТУТ БУЛО. Правило, що порівнює колір двох речей, саме складало відношення з примітивів,
# двома гілками: для двох вимірів — `кут_на_колі(h, h) <= ДУГА_ВІДЛУННЯ`, для вікна слова —
# `відлуння_тону(a, b) != "ні"` (групи фокусів K-CRA-02, K-COL-05 у `колір_хрома` і
# `суд_від_моделі`, «що лишити» K-COL-02, голоси K-PAL-15, `palettes`, K-ACC-01), а
# комплемент K-PAL-05 — порогом 150° над `розкид_тону_на_колі`. Кожне місце мало свій шлях
# до того самого «той самий тон?», і нове відношення (сусідні сектори, тріада) довелося б
# складати вкотре.
# ЩО СТАЛО. Колір речі — `запис_кольору`: межі L* і C* (CIELAB), дуга тону на колі художника
# (R 0°, G 180°; `colorspace.у_коло_художника`, те саме коло, що схеми палітри), сектори
# 12-кольорового кола, свідок кодом, довіра, гучність. Відношення двох кольорів — одна
# функція `відношення(a, b, клас)` → «так» / «ні» / «невідомо» над класами
# `КЛАСИ_ВІДНОШЕНЬ` (межі — PR #717, «Художні межі»: K-COL-03, K-PAL-04, `RELATIONS`,
# K-COL-01, K-COL-02, K-COL-06). Два виміри — «так» чи «ні»; вікно слова — «так», коли так
# каже кожна точка вікон, «ні» — коли жодна, інакше «невідомо». Хвиля 1 рішень не міняє:
# правила, що після Р2 міряли на колі, дістають ті самі вердикти (`проби/колір_відношення_пари.py`).
# Правила, що читають `lab` точкою, переходять на це API хвилею 2 (після КОЛІР-Р1); назви
# свідків рядками (`колір_не_вимір.свідок`) і сімей — хвилею 3.
# ДЕ ЛАМАЄТЬСЯ: клас-кон'юнкція («echo» = той самий тон ∧ без кроку світлоти ∧ обидва
# гучні) судиться за Кліні з умов, кожна з яких — над усім вікном окремо, тож «так» і «ні»
# правдиві завжди, але «невідомо» може стояти там, де спільна точка вікон вирішила б.
# Вимір — точка без допуску (як у Р2); допуск виміру тону (`допуск_тону`) — питання хвилі 2.
СЕКТОР_КОЛА = 30.0          # крок 12-кольорового кола художника (R 0°, RO 30°, O 60°, …)

# Свідок кольору кодом. Ключі — рядки, які нині пише фід у `колір_не_вимір.свідок`
# (`фід_збагачення.не_вимір_кольору`, `річ_з_фото`, `композитор_річ`); хвиля 3 — фід пише код
# одразу, і таблиця зникає. Колір без поля — вимір (шапка секції вище).
СВІДОК_КОД = {"слово крамниці": "shop_word", "слово моделі": "model_word",
              "hex моделі": "model_hex", "її слово": "her_word"}


def сектор_кола(k):
    """Номер сектора 12-кольорового кола (0 — R, 1 — RO, … 11) для кута кола художника `k`."""
    return int(((k + СЕКТОР_КОЛА / 2) % 360.0) // СЕКТОР_КОЛА)


def _сектори(дуга):
    """Сектори кола, яких торкається дуга (k0, k1) кола художника, за ходом від k0 до k1."""
    if (дуга[1] - дуга[0]) % 360.0 > 360.0 - СЕКТОР_КОЛА:
        return tuple(range(12))
    с, к = сектор_кола(дуга[0]), сектор_кола(дуга[1])
    сс = [с]
    while сс[-1] != к:
        сс.append((сс[-1] + 1) % 12)
    return tuple(сс)


def запис_кольору(x):
    """Колір речі чи елемента одним записом для всіх правил; None — кольору нема.

    dict(L=(L0, L1), C=(C0, C1) — межі CIELAB; коло=(k0, k1) — дуга тону на колі
    художника (вимір — k0 = k1; None — ахроматичне слово, тон будь-який); сектори — номери
    `сектор_кола`, яких торкається дуга (None — без тону); свідок — код («measure» — вимір,
    коди `СВІДОК_КОД`, «unknown»); довіра — 1.0 вимір, None — вікно слова (невизначеність
    — у межах; згоди свідків фід на запис не кладе); гучний — «так» / «можливо» / «ні»)."""
    м = межі_кольору(x)
    if м is None:
        return None
    нв, дуга = не_вимір(x), _дуга_на_колі(м)
    return dict(L=(м[0], м[1]), C=(м[2], м[3]), коло=дуга,
                сектори=None if дуга is None else _сектори(дуга),
                свідок="measure" if нв is None else СВІДОК_КОД.get(нв.get("свідок"), "unknown"),
                довіра=1.0 if нв is None else None, гучний=гучність_меж(x))


def _у_смузі(р, lo, hi=float("inf"), відкрита=False):
    """«так» / «ні» / «невідомо»: чи величина з інтервалу р = (мін, макс) лежить у смузі
    [lo, hi] (`відкрита` — lo не входить). Інтервал суцільний: на ньому досяжне кожне
    значення між мін і макс (відстань між точками дуг чи відрізків неперервна)."""
    над = (lambda v: v > lo) if відкрита else (lambda v: v >= lo)
    if над(р[0]) and р[1] <= hi:
        return "так"
    return "ні" if р[0] > hi or not над(р[1]) else "невідомо"


def _і(*вв):
    """Кон'юнкція Кліні над «так» / «ні» / «невідомо» («можливо» — те саме, що «невідомо»)."""
    return "ні" if "ні" in вв else "так" if all(в == "так" for в in вв) else "невідомо"


def _не(в):
    """Заперечення Кліні: «невідомо» (і «можливо») лишається «невідомо»."""
    return {"так": "ні", "ні": "так"}.get(в, "невідомо")


def _або(*вв):
    """Диз'юнкція Кліні (за де Морганом через `_і`)."""
    return _не(_і(*map(_не, вв)))


