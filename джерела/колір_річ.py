def одна_на_річ(E):
    """`елементи()` віддає по запису на КОЖЕН КОЛІР речі: принтована сукня з трьома
    кольорами — це три записи. Правила, які РАХУЮТЬ (скільки шарів, скільки поверхонь
    блиску, скільки відкритих зон, скільки гучних елементів), мусять рахувати РЕЧІ.
    Інакше одна сукня давала «відкрито 3 зони (декольте, декольте, декольте)» і
    з'їдала весь бюджет блиску сама собою — відтворено на реальному форматі
    feed.палітра_принту, який саме кілька кольорів на річ і віддає.

    Лишається запис із НАЙБІЛЬШОЮ площею — він і несе властивості речі."""
    по = {}
    for e in E:
        cur = по.get(e["річ"])
        if cur is None or (e.get("площа") or 0.0) > (cur.get("площа") or 0.0):
            по[e["річ"]] = e
    return [по[r] for r in dict.fromkeys(e["річ"] for e in E)]

def _групи_речей(E):
    """Річ -> усі її колірні елементи (для правил, яким потрібна СУМА площ речі)."""
    g = {}
    for e in E: g.setdefault(e["річ"], []).append(e)
    return g

