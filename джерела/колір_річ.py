# ЩО ТУТ БУЛО. Колір зі слова (крамниці чи моделі) заходив у запис каталогу ЦЕНТРОМ
# ВІКНА лексикону, і кожне правило, що порівнює колір ДВОХ РЕЧЕЙ, брало цей центр за
