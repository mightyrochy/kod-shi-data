# ЩО ТУТ БУЛО. K-COL-01 (`колір_світлота`), K-COL-06 (`колір_нейтралі`), K-PAL-15 (`суд_від_моделі`)
# брали `розкид_осі(a, b, "L")` і самі порівнювали з кроком; K-COL-06 і K-ACC-10 — `de00_мін`
# з порогом; «два різні білі» і R-COL-16 — `межі_b` з межею b*; конфлікт хром K-COL-02 —
# `розкид_тону` з 45° CIELAB; комплемент K-PAL-05 на вимірі — тон точкою на колі. Кожне місце
# складало «так / ні / невідомо» з інтервалу по-своєму.
# ЩО СТАЛО. Те саме питання — клас `відношення`: `value_step` (ΔL*), `distinct` (ΔE00 між
# найближчими краями, K-COL-06 «видимо різні» > 6), `warmer` (b* першого вище b* другого,
# K-COL-06 / R-COL-16; межу чи вікно палітри правило подає опорною точкою `опора_b`),
# `near_hue` (той самий чи сусідній сектор кола художника, ≤45° — K-COL-02: далі — два різні
# кольори, що б'ються). `поріг` зсуває межу класу, де правило стоїть над похибкою входу
# (K-COL-06: крок мінус шум ΔL* фото), `міра` віддає інтервал, яким клас судив, — число для
# тексту знахідки і сили (Δ кола, ΔL*, ΔE00, Δb*), щоб правило не міряло вдруге.
# ДЕ ЛАМАЄТЬСЯ: `distinct` на вікні слова — ОЦІНКА мінімуму ΔE00 (див. `de00_мін`), і «ні»
# він каже лише на двох вимірах: максимуму ΔE00 вікна код не рахує.
ΔE_ВИДИМО = 6.0     # K-COL-06: дві нейтралі однієї світлоти «видимо різні» від ΔE00 > 6


def _розведені(п):
    """Клас `distinct`: ΔE00 між найближчими краями кольорів понад поріг (типово `ΔE_ВИДИМО`)."""
    д = de00_мін(п["a"], п["b"])
    if д is None:
        return "невідомо"
    if д > п["поріг"]:
        return "так"
    return "ні" if не_вимір(п["a"]) is None and не_вимір(п["b"]) is None else "невідомо"


def _різниця_b(a, b):
    """(мін, макс) b*(a) − b*(b) за `межі_b`; None — котрогось кольору нема."""
    ба, бб = межі_b(a), межі_b(b)
    return None if ба is None or бб is None else (ба[0] - бб[1], ба[1] - бб[0])


def _тепліший(п):
    """Клас `warmer`: b* першого понад b* другого більше ніж на поріг (типово 0)."""
    р = _різниця_b(п["a"], п["b"])
    if р is None:
        return "невідомо"
    return "так" if р[0] > п["поріг"] else "ні" if р[1] <= п["поріг"] else "невідомо"


