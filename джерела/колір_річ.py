FAMILIES = [(340,45,"червона/рожева"), (45,70,"помаранчева/теракота"), (70,100,"жовта"),
            (100,140,"жовто-зелена"), (140,180,"зелена"), (180,250,"синьо-зелена"),
            (250,310,"синя"), (310,340,"фіолетова/маджента")]
def сім_я(lab):
    """Сім'я кольору речі: «нейтраль-<рід>» для нейтралі, інакше одна з восьми дуг `FAMILIES` за кутом
    тону, або «невизначена».

    Чому так: `FAMILIES` — розбиття кола без проміжків і перетинів, з межами,
    виміряними на якорях у цьому ж просторі; тому воно рахує КІЛЬКІСТЬ сімей і шукає
    відлуння, але вердикту «личить» не виносить (кут CIELAB у синьо-фіолетовій
    ділянці неоднорідний — коментар над таблицею)."""
    n = нейтраль(lab)
    if n: return f"нейтраль-{n}"
    _,_,h = lch(lab)
    for lo,hi,nm in FAMILIES:
        if (lo<=h<hi) if lo<hi else (h>=lo or h<hi): return nm
    return "невизначена"


