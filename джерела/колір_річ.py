def річ_у_класі(x, клас):
    """Чи колір речі (чи елемента) ВЕСЬ лежить у вікні класу: True / False / None.

    None — колірного входу нема зовсім (`межі_кольору` і назва мовчать) або класу не
    знаємо: тоді річ не чіпають. True лише тоді, коли вікно речі ціле всередині вікна
    класу — вікно, що лежить по обидва боки порога, лишається в пулі (шапка секції).
    Свідків двоє: вимір (чи вікно слова крамниці) і слово кольору в назві речі —
    досить одного, бо це межа людини, а тут хибне спрацювання коштує однієї речі,
    а пропуск — довіри (той самий обмін, що в `profile.жорстке_ні_фільтр`)."""
    в = КЛАСИ_КОЛЬОРУ.get(клас)
    if в is None or not isinstance(x, dict):
        return None
    свідки = [м for м in (межі_кольору(x), _вікно_назви(x)) if м]
    if not свідки:
        return None
    return any(_у_вікні(в, м) for м in свідки)
