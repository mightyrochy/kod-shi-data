# ЩО СТАЛО. Запис речі несе поле `колір_не_вимір` (його ставлять `фід_каталог` і
# `фід_збагачення`), елемент кольору — теж (`outfit.елементи`). Правило, що міряє
# ΔE, тон, світлоту чи хрому МІЖ РЕЧАМИ, судить вимір як доти; де хоч один колір
# пари — не вимір, воно або вирішує НА РІВНІ ВІКОН (межі вікна слова — правда про
# колір, центр — ні), і каже про це у знахідці, або віддає чесне «без входу» з
# названим полем (`без_входу_кольору`): не «збігаються» і не «не збігаються».
# Колір без поля провенансу лишається виміром: синтетика проб, гардероб людини й
# піксельний шлях подають hex як факт, і саме так їх судили доти.

def не_вимір(x):
    """`колір_не_вимір` речі чи елемента — коли колір НЕ вимір; None — вимір.

    Поле — dict: `свідок` («слово крамниці», «слово моделі», «hex моделі»),
    `слово` лексикону, `вікно` у формі `verify.ЛЕКСИКОН`, `чому` — рядок для
    людини. Колір без поля — вимір (див. шапку секції)."""
    нв = x.get("колір_не_вимір") if isinstance(x, dict) else None
    return нв if isinstance(нв, dict) and нв else None


def межі_кольору(x):
    """(L0, L1, C0, C1, дуга) — де лежить колір речі чи елемента.

    Вимір — точка: L0 = L1, C0 = C1, дуга (h, h). Не вимір — вікно слова з
    `колір_не_вимір["вікно"]` (дуга None — ахроматичне слово, тон будь-який).
    None — колір не виміряний і вікна нема, або кольору нема зовсім."""
    нв = не_вимір(x)
    if нв is not None:
        в = нв.get("вікно")
        if not в or len(в) < 5:
            return None
        return (float(в[0]), float(в[1]), float(в[2]), float(в[3]),
                None if в[4] is None else (float(в[4][0]), float(в[4][1])))
    lab = x.get("lab") if isinstance(x, dict) else None
    if not lab:
        return None
    L, Cc, h = lch(tuple(lab))
    return (L, L, Cc, Cc, (h, h))


def _на_дузі(h, дуга):
    """Чи тон h лежить на дузі (lo, hi); дуга з переходом через 0° (lo > hi) — теж."""
    lo, hi = дуга
    return (lo <= h <= hi) if lo <= hi else (h >= lo or h <= hi)


def _кут(a, b):
    """Коротша кутова відстань між двома тонами, 0…180°."""
    d = abs(a - b) % 360.0
    return min(d, 360.0 - d)


def розкид_тону(a, b):
    """(мін, макс) кутової відстані тонів двох речей чи елементів.

    Два виміри — одне число двічі. Вікно — усе, що дозволяють його дуги: мінімум 0,
    коли дуги перетинаються, максимум 180, коли дуга однієї заходить навпроти
    другої; інакше обидва — на кінцях дуг (відстань між дугами кусково-лінійна).
    Ахроматичне слово тону не має — (0, 180). None — котрогось кольору нема."""
    ма, мб = межі_кольору(a), межі_кольору(b)
    if ма is None or мб is None:
        return None
    да, дб = ма[4], мб[4]
    if да is None or дб is None:
        return (0.0, 180.0)
    кінці = [(x, y) for x in да for y in дб]
    перетин = any(_на_дузі(k, дб) for k in да) or any(_на_дузі(k, да) for k in дб)
    навпроти = ((дб[0] + 180.0) % 360.0, (дб[1] + 180.0) % 360.0)
    протилежні = any(_на_дузі(k, навпроти) for k in да) or any(_на_дузі(k, да) for k in навпроти)
    return (0.0 if перетин else min(_кут(x, y) for x, y in кінці),
            180.0 if протилежні else max(_кут(x, y) for x, y in кінці))


def поруч_за_тоном(a, b, поріг):
    """«так» / «ні» / «невідомо»: чи тони двох речей у межах `поріг` градусів.

    Два виміри — звичайне порівняння. Де хоч один колір — вікно слова, «так» лише
    коли ВСЕ вікно в межах порога, «ні» — коли жодна його точка туди не дістає;
    інакше «невідомо», і правило, що групує тони (K-COL-05), не має права ні
    зараховувати пару до одного голосу, ні розводити її."""
    р = розкид_тону(a, b)
    if р is None:
        return "невідомо"
    if р[0] > поріг:
        return "ні"
    if р[1] <= поріг:
        return "так"
    return "невідомо"


def розкид_осі(a, b, вісь):
    """(мін, макс) |Δ| світлоти (`вісь="L"`) чи хроми CIELab (`вісь="C"`) двох речей.

    Два виміри — одне число двічі; вікно — від зазору між відрізками (0, коли вони
    перетинаються) до найдальших кінців. None — котрогось кольору нема."""
    ма, мб = межі_кольору(a), межі_кольору(b)
    if ма is None or мб is None:
        return None
    i = 0 if вісь == "L" else 2
    a0, a1, b0, b1 = ма[i], ма[i + 1], мб[i], мб[i + 1]
    return (max(0.0, a0 - b1, b0 - a1), max(a1 - b0, b1 - a0))


def межі_b(x):
    """(мін, макс) b* кольору речі чи елемента: вимір — одне число двічі, вікно — усе,
    що дозволяють його хрома й дуга (b* = C·sin h). None — кольору нема.

    Читає K-COL-06 «два різні білі»: теплий білий від оптичного відділяє b*, і
    «вершковий» біля «оптичного» стверджується лише тоді, коли весь інтервал
    кожного лежить по свій бік межі."""
    import math as _м
    м = межі_кольору(x)
    if м is None:
        return None
    if не_вимір(x) is None:
        b = float(x["lab"][2])
        return (b, b)
    C0, C1, д = м[2], м[3], м[4]
    if д is None:
        return (-C1, C1)
    синуси = [_м.sin(_м.radians(k)) for k in д]
    if _на_дузі(90.0, д):
        синуси.append(1.0)
    if _на_дузі(270.0, д):
        синуси.append(-1.0)
    значення = [Cc * sn for Cc in (C0, C1) for sn in (min(синуси), max(синуси))]
    return (min(значення), max(значення))


def _найближчі(a0, a1, b0, b1):
    """Пара найближчих значень двох відрізків; коли вони перетинаються — спільна точка."""
    if a1 < b0:
        return a1, b0
    if b1 < a0:
        return a0, b1
    к = (max(a0, b0) + min(a1, b1)) / 2.0
    return к, к


def _найближчі_тони(да, дб):
    """Пара найближчих тонів двох дуг; ахроматична дуга (None) бере тон другої."""
    if да is None and дб is None:
        return 0.0, 0.0
    if да is None:
        return дб[0], дб[0]
    if дб is None:
        return да[0], да[0]
    for k in да:
        if _на_дузі(k, дб):
            return k, k
    for k in дб:
        if _на_дузі(k, да):
            return k, k
    return min(((x, y) for x in да for y in дб), key=lambda п: _кут(*п))


def de00_мін(a, b):
    """ΔE00 між НАЙБЛИЖЧИМИ краями кольорів двох речей — нижня оцінка НА РІВНІ ВІКОН.

    Два виміри — сама ΔE00. Де хоч один колір — вікно слова, береться найближча
    пара точок двох вікон за світлотою, хромою й тоном. Межа названа: ΔE00 не
    лінійна (ваги S_L, S_C, S_H залежать від середнього кольору пари), тож це ОЦІНКА
    мінімуму, а не доведена межа; споживачі кажуть «на рівні вікон», а не «виміряно».
    None — котрогось кольору нема."""
    import math as _м
    from colorspace import de00 as _de00
    if не_вимір(a) is None and не_вимір(b) is None:
        if not (a.get("lab") and b.get("lab")):
            return None
        return _de00(tuple(a["lab"]), tuple(b["lab"]))
    ма, мб = межі_кольору(a), межі_кольору(b)
    if ма is None or мб is None:
        return None
    La, Lb = _найближчі(ма[0], ма[1], мб[0], мб[1])
    Ca, Cb = _найближчі(ма[2], ма[3], мб[2], мб[3])
    ha, hb = _найближчі_тони(ма[4], мб[4])
    лаб = lambda L, Cc, h: (L, Cc * _м.cos(_м.radians(h)), Cc * _м.sin(_м.radians(h)))
    return _de00(лаб(La, Ca, ha), лаб(Lb, Cb, hb))


def назва_коротко(назва, межа=40):
    """Назва речі для рядка людині: ціла, коли коротка; інакше обрізана ПО МЕЖІ СЛОВА з «…»."""
    н = str(назва or "").strip()
    if len(н) <= межа:
        return н
    зріз = н[:межа].rsplit(" ", 1)[0].rstrip(",;:—-(")
    return (зріз or н[:межа]) + "…"


def _слово_кольору(x):
    """Коротко, чим є колір речі, для рядка людині: «центр вікна слова «X»» чи «вимір»."""
    нв = не_вимір(x)
    if нв is None:
        return "вимір"
    if нв.get("свідок") == "hex моделі":
        return "hex, названий моделлю до слова «%s»" % нв.get("слово")
    return "центр вікна слова «%s»" % нв.get("слово")


def без_входу_кольору(правило, пари, що, чому_правило):
    """Знахідка-питання «без входу» для правила, що порівнює колір РЕЧЕЙ, коли колір
    бодай однієї речі — не вимір (CLAUDE.md п.4: названим полем, не мовчанням).

    `пари` — кортежі з однієї або двох речей чи елементів (поля `річ`/`id`, `назва`,
    `колір_не_вимір`), над якими правило не може вирішити: пара — для попарного
    правила, одна річ — для правила над набором (середнє, розмах, група). `що` — яке
    твердження правило не може ні зробити, ні спростувати; `чому_правило` — навіщо
    правилу саме вимір. `без_входу` і `бракує` читає `суд_чеклісти` (пункт правила
    стає «без входу» з названим полем); регістр «питання» везе рядок у «код не
    знає» картки й звіту. У ключ ранжування він не входить: сила 0, а брак входу —
    не вада речі."""
    ід = lambda x: x.get("річ") or x.get("id")
    назва = lambda x: "«%s»" % назва_коротко(x.get("назва") or ід(x), 32)
    описи, речі, деталі, бачені = [], [], [], set()
    for п in пари:
        п = [x for x in п if isinstance(x, dict)]
        if not п or frozenset(map(ід, п)) in бачені:
            continue
        бачені.add(frozenset(map(ід, п)))
        слова = [_слово_кольору(x) for x in п]
        if len(п) == 2 and слова[0] == слова[1]:
            описи.append("%s і %s — обидва кольори: %s" % (назва(п[0]), назва(п[1]), слова[0]))
        else:
            описи.append(", ".join("%s — %s" % (назва(x), с) for x, с in zip(п, слова)))
        for x in п:
            нв = не_вимір(x)
            if нв is not None and ід(x) not in речі:
                речі.append(ід(x))
                деталі.append("%s: %s" % (назва(x), нв.get("чому") or "не вимір"))
    опис = "; ".join(dict.fromkeys(описи))
    return dict(правило=правило, сила="питання", регістр="питання", сила_нп=0.0,
                сила_нп_джерело="входу нема: колір речі не виміряний (поле «колір_не_вимір»)",
                суть="%s — код не знає: %s" % (що, опис), речі=речі,
                без_входу="колір_не_вимір",
                бракує=("виміряний колір речей (поле «колір_не_вимір» у виміру порожнє) — "
                        + "; ".join(деталі)),
                чому=(чому_правило + ". Колір зі слова — це ВІКНО лексикону, а не точка: "
                      "центр вікна однаковий для всіх речей із тим самим словом, і різниця "
                      "між ними дорівнює нулю за побудовою, а не за виміром"),
                ремонт=("виміряти колір цих речей із фото (жнива v2: маска речі й k-means "
                        "у Lab) — доти правило над ними не судить ні в той, ні в інший бік"),
                ламається=("вікно слова інколи дозволяє вирішити й без виміру (вікна "
                           "розведені далі за поріг) — тоді вирішує саме правило й каже "
                           "це у знахідці; тут лишились ті, де вікна сходяться"))
