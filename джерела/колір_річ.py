# ЩО ТУТ БУЛО. Добір пулу (`композитор_слоти.добір_дуги`, основа й сім'ї схеми в `міст_пакет`,
# `палітра_схеми.сім_я_схеми`) читав тон і хрому `lab` точкою, а в речі зі слова це центр вікна
# слова; вікно речі композитор брав із поля `вікно`, яке пише лише гілка слова крамниці, тож hex
# і слово моделі (не вимір, `колір_не_вимір`) стояли в доборі точкою, а в суді — вікном.
# ЩО СТАЛО. `вікно_речі` — вікно кольору, коли він не вимір; клас `within` — колір речі в межах
# вікна-опори (`опора_вікна`: смуги L*, C*, дуга тону), «так» — цілком, «невідомо» — частково.
def опора_вікна(L=(0.0, 100.0), C=(0.0, 1000.0), дуга=None):
    """Опора для класу `within`: вікно палітри чи схеми як колір-вікно — смуги L*, C* і дуга
    тону CIELAB (lo, hi) з обходом 0° (None — тон будь-який)."""
    return dict(колір_не_вимір=dict(свідок="опора", вікно=(
        float(L[0]), float(L[1]), float(C[0]), float(C[1]),
        None if дуга is None else (float(дуга[0]) % 360.0, float(дуга[1]) % 360.0))))


def вікно_речі(x):
    """Вікно (L0, L1, C0, C1, дуга) кольору речі, коли колір НЕ вимір (слово крамниці, слово чи
    hex моделі, невідомий); None — вимір (точка) або кольору нема. Добір судить таку річ
    вікном, а не точкою свого `lab` (п.18)."""
    return межі_кольору(x) if не_вимір(x) is not None else None


def _смуга_в(а, б):
    """Чи відрізок а = (мін, макс) лежить у б: «так» — цілком, «ні» — без перетину."""
    if а[0] >= б[0] and а[1] <= б[1]:
        return "так"
    return "ні" if а[1] < б[0] or а[0] > б[1] else "невідомо"


def _дуга_в(да, дб):
    """Чи дуга тону а лежить у дузі б на колі (обидві — (від, до) з обходом 0°; None —
    тон будь-який): «так» — цілком, «ні» — без перетину, інакше «невідомо»."""
    if дб is None:
        return "так"
    if да is None:
        return "невідомо"
    ша, шб = (да[1] - да[0]) % 360.0, (дб[1] - дб[0]) % 360.0
    if _на_дузі(да[0], дб) and (да[0] - дб[0]) % 360.0 + ша <= шб + 1e-9:
        return "так"
    перетин = any(_на_дузі(k, дб) for k in да) or any(_на_дузі(k, да) for k in дб)
    return "невідомо" if перетин else "ні"


def _всередині(а, б):
    """Клас `within`: колір a цілком у вікні b — L*, C* і дуга кола художника (Кліні)."""
    return _і(_смуга_в(а["L"], б["L"]), _смуга_в(а["C"], б["C"]), _дуга_в(а["коло"], б["коло"]))


def опора_b(b):
    """Опорна точка для класу `warmer`: вимір із b* = `b` (межа теплого білого, край вікна
    палітри — K-COL-06, R-COL-16)."""
    return dict(lab=(50.0, 0.0, float(b)))


_ВІДНОШЕННЯ = {
    # той самий сектор кола (±15°) — один голос тону (Р2а; K-COMP-05, K-COL-05, K-CRA-02)
    "same_hue": lambda т, L, а, б, п: _у_смузі(т, 0.0, ДУГА_ВІДЛУННЯ),
    # сусідній сектор — аналогова пара, потрібен крок світлоти (K-PAL-04)
    "adjacent": lambda т, L, а, б, п: _у_смузі(т, ДУГА_ВІДЛУННЯ, ДУГА_ВІДЛУННЯ + СЕКТОР_КОЛА, True),
    # той самий чи сусідній сектор (≤45°): далі — два різні кольори (конфлікт хром K-COL-02)
    "near_hue": lambda т, L, а, б, п: _у_смузі(т, 0.0, ДУГА_ВІДЛУННЯ + СЕКТОР_КОЛА),
    "triadic": lambda т, L, а, б, п: _у_смузі(т, RELATIONS["triadic"][0] - RELATIONS["triadic"][1],
                                            RELATIONS["triadic"][0] + RELATIONS["triadic"][1]),
    "split": lambda т, L, а, б, п: _у_смузі(т, RELATIONS["split"][0] - RELATIONS["split"][1],
                                          RELATIONS["split"][0] + RELATIONS["split"][1]),
    # K-COL-03 §4 (бордо ↔ хвоя, кемел ↔ темно-синій, бірюза ↔ мідь), K-PAL-05: ≥150°
    "complementary": lambda т, L, а, б, п: _у_смузі(
        т, RELATIONS["complementary"][0] - RELATIONS["complementary"][1]),
    # різні кроки світлоти (K-COL-01; поріг — `step_min`)
    "value_step": lambda т, L, а, б, п: _у_смузі(L, C["step_min"] if п["поріг"] is None else п["поріг"]),
    # тон-у-тон: той самий сектор і крок світлоти (K-COL-03 §2, K-PAL-03)
    "tonal": lambda т, L, а, б, п: _і(_у_смузі(т, 0.0, ДУГА_ВІДЛУННЯ), _у_смузі(L, C["step_min"])),
    # відлуння: той самий акцент у двох точках — сектор, без кроку світлоти, обидва гучні
    "echo": lambda т, L, а, б, п: _і(_у_смузі(т, 0.0, ДУГА_ВІДЛУННЯ), _не(_у_смузі(L, C["step_min"])),
                                   а["гучний"], б["гучний"]),
    # гучний біля нейтралі (K-COL-02, K-COL-06: нейтраль — C* < `neutral_C`)
    "chroma_contrast": lambda т, L, а, б, п: _або(
        _і(а["гучний"], _не(_у_смузі(б["C"], C["neutral_C"]))),
        _і(б["гучний"], _не(_у_смузі(а["C"], C["neutral_C"])))),
    # видимо різні: ΔE00 найближчих країв понад поріг (K-COL-06 > 6; K-ACC-10 — точний збіг)
    "distinct": lambda т, L, а, б, п: _розведені(dict(п, поріг=ΔE_ВИДИМО if п["поріг"] is None else п["поріг"])),
    # перший тепліший за другий: b* понад (K-COL-06 два різні білі, R-COL-16 вікно палітри)
    "warmer": lambda т, L, а, б, п: _тепліший(dict(п, поріг=0.0 if п["поріг"] is None else п["поріг"])),
    # колір першого цілком у вікні другого (опора `опора_вікна`: дуга схеми з нижньою межею
    # хроми — добір дуги, основа, сім'ї схеми); напрямлений
    "within": lambda т, L, а, б, п: _всередині(а, б),
}
КЛАСИ_ВІДНОШЕНЬ = tuple(_ВІДНОШЕННЯ)
_МІРА_ТОНУ = ("same_hue", "adjacent", "near_hue", "triadic", "split", "complementary")


def відношення(a, b, клас=None, поріг=None, міра=False):
    """Відношення кольорів двох речей чи елементів: «так» / «ні» / «невідомо».

    `клас` — один із `КЛАСИ_ВІДНОШЕНЬ` → вердикт рядком; без класу → {клас: вердикт}.
    Кольору котроїсь речі нема — «невідомо» в кожному класі. Тон — на колі художника
    (`запис_кольору`), світлота й хрома — межі CIELAB. `warmer` і `within` напрямлені (a щодо
    b), решта — симетричні.
    `поріг` — межа класу замість типової: `value_step` (ΔL*, типово `step_min`), `distinct`
    (ΔE00, типово `ΔE_ВИДИМО`), `warmer` (Δb*, типово 0); межі тонових класів дає коло, поріг їх
    не зсуває. `міра=True` (з класом) → (вердикт, (мін, макс)) — інтервал, яким клас судив:
    Δ тону на колі художника, ΔL*, ΔE00 (мін, None — максимуму код не рахує), b*(a) − b*(b);
    кон'юнкції (`tonal`, `echo`, `chroma_contrast`) і відсутній колір — None."""
    ра, рб = запис_кольору(a), запис_кольору(b)
    класи = КЛАСИ_ВІДНОШЕНЬ if клас is None else (клас,)
    м = None
    if ра is None or рб is None:
        вв = {к: "невідомо" for к in класи}
    else:
        т = _розкид_дуг(ра["коло"], рб["коло"])
        L = (max(0.0, ра["L"][0] - рб["L"][1], рб["L"][0] - ра["L"][1]),
             max(ра["L"][1] - рб["L"][0], рб["L"][1] - ра["L"][0]))
        п = dict(a=a, b=b, поріг=поріг)
        вв = {к: _ВІДНОШЕННЯ[к](т, L, ра, рб, п) for к in класи}
        if міра and клас is not None:
            м = (т if клас in _МІРА_ТОНУ else L if клас == "value_step" else
                 (de00_мін(a, b), None) if клас == "distinct" else
                 _різниця_b(a, b) if клас == "warmer" else None)
    if клас is None:
        return вв
    return (вв[клас], м) if міра else вв[клас]


def розкид_осі(a, b, вісь):
    """(мін, макс) |Δ| світлоти (`вісь="L"`) чи хроми CIELab (`вісь="C"`) двох речей.

    Два виміри — одне число двічі; вікно — від зазору між відрізками (0, коли вони
    перетинаються) до найдальших кінців. None — котрогось кольору нема."""
    ма, мб = межі_кольору(a), межі_кольору(b)
    if ма is None or мб is None:
        return None
    i = 0 if вісь == "L" else 2
    a0, a1, b0, b1 = ма[i], ма[i + 1], мб[i], мб[i + 1]
    return (max(0.0, a0 - b1, b0 - a1), max(a1 - b0, b1 - a0))


def межі_b(x):
    """(мін, макс) b* кольору речі чи елемента: вимір — одне число двічі, вікно — усе,
    що дозволяють його хрома й дуга (b* = C·sin h). None — кольору нема.

    Читає K-COL-06 «два різні білі»: теплий білий від оптичного відділяє b*, і
    «вершковий» біля «оптичного» стверджується лише тоді, коли весь інтервал
    кожного лежить по свій бік межі."""
    import math as _м
    м = межі_кольору(x)
    if м is None:
        return None
    if не_вимір(x) is None:
        b = float(x["lab"][2])
        return (b, b)
    C0, C1, д = м[2], м[3], м[4]
    if д is None:
        return (-C1, C1)
    синуси = [_м.sin(_м.radians(k)) for k in д]
    if _на_дузі(90.0, д):
        синуси.append(1.0)
    if _на_дузі(270.0, д):
        синуси.append(-1.0)
    значення = [Cc * sn for Cc in (C0, C1) for sn in (min(синуси), max(синуси))]
    return (min(значення), max(значення))


def _найближчі(a0, a1, b0, b1):
    """Пара найближчих значень двох відрізків; коли вони перетинаються — спільна точка."""
    if a1 < b0:
        return a1, b0
    if b1 < a0:
        return a0, b1
    к = (max(a0, b0) + min(a1, b1)) / 2.0
    return к, к


def _найближчі_тони(да, дб):
    """Пара найближчих тонів двох дуг; ахроматична дуга (None) бере тон другої."""
    if да is None and дб is None:
        return 0.0, 0.0
    if да is None:
        return дб[0], дб[0]
    if дб is None:
        return да[0], да[0]
    for k in да:
        if _на_дузі(k, дб):
            return k, k
    for k in дб:
        if _на_дузі(k, да):
            return k, k
    return min(((x, y) for x in да for y in дб), key=lambda п: _кут(*п))


def de00_мін(a, b):
    """ΔE00 між НАЙБЛИЖЧИМИ краями кольорів двох речей — нижня оцінка НА РІВНІ ВІКОН.

    Два виміри — сама ΔE00. Де хоч один колір — вікно слова, береться найближча
    пара точок двох вікон за світлотою, хромою й тоном. Межа названа: ΔE00 не
    лінійна (ваги S_L, S_C, S_H залежать від середнього кольору пари), тож це ОЦІНКА
    мінімуму, а не доведена межа; споживачі кажуть «на рівні вікон», а не «виміряно».
    None — котрогось кольору нема."""
    import math as _м
    from colorspace import de00 as _de00
    if не_вимір(a) is None and не_вимір(b) is None:
        if not (a.get("lab") and b.get("lab")):
            return None
        return _de00(tuple(a["lab"]), tuple(b["lab"]))
    ма, мб = межі_кольору(a), межі_кольору(b)
    if ма is None or мб is None:
        return None
    La, Lb = _найближчі(ма[0], ма[1], мб[0], мб[1])
    Ca, Cb = _найближчі(ма[2], ма[3], мб[2], мб[3])
    ha, hb = _найближчі_тони(ма[4], мб[4])
    лаб = lambda L, Cc, h: (L, Cc * _м.cos(_м.radians(h)), Cc * _м.sin(_м.radians(h)))
    return _de00(лаб(La, Ca, ha), лаб(Lb, Cb, hb))


# ── ЧИ НЕСЕ РІЧ ТОН ДУГИ СХЕМИ: ВІКНО СЛОВА, А НЕ ЙОГО ЦЕНТР (24.09.2026, рядок 162) ──
# Доти `міст_пакет._несе_колір` питав ТОЧКУ: lab речі в дузі ±12° і не нейтраль.
# Для кольору зі слова ця точка — центр вікна лексикону, однаковий у всіх речей із
# тим самим словом (на 3 251 річ акцентних слотів каталогу — 937 різних lab), і
# вузька дуга падала МІЖ центрами слів: очі стенда (h 172°) — 2 речі на весь
# каталог, хоч синьо-зелених речей там 41. Рішення власника 20.09 про лексикон:
# вікно слова — те, як слово вживають крамниці й модель. Тож колір-слово несе тон,
# коли слово називає колір (центр вікна — не нейтраль за K-COL-06, тією самою межею,
# якою й доти відсіювались нейтралі), а дуга тону ВІКНА перетинає дугу схеми.
# Виміряний колір — точка з допуском виміру: кут, під яким видно похибку в одну
# ледь помітну різницю (ΔE*ab ≈ 2.3, Sharma 2003 — CIE76 JND) на хромі речі, не
# ширший за 10° — той самий запас дуги, що в `фід_добір.описує_річ` і
# `pipeline.схема_образу`. ПЕРЕГЛЯНУТИ, коли повторюваність тону з фото (жнива v2,
# маска + k-means) буде виміряна на каталозі: тоді допуск — її розкид.
ТОН_JND_ΔE = 2.3
ТОН_ДОПУСК_МАКС = 10.0


def допуск_тону(Cc):
    """Кутовий допуск виміряного тону (°) на хромі `Cc`: atan(JND / C*), не ширший за 10°."""
    import math as _м
    return min(ТОН_ДОПУСК_МАКС, _м.degrees(_м.atan2(ТОН_JND_ΔE, max(float(Cc), 1e-9))))



def несе_тон(x, дуга):
    """«вимір» / «слово» / None — чи колір речі несе тон дуги схеми (lo, hi), з обходом 0°.

    Вимір (поля `колір_не_вимір` нема): точка не нейтраль і тон у дузі з допуском
    `допуск_тону`. Колір зі слова: слово називає колір (центр його вікна — не нейтраль)
    і дуга тону вікна перетинає дугу схеми (ахроматичне слово без дуги тону не несе).
    None — ні, або кольору нема."""
    if not дуга:
        return None
    lo, hi = float(дуга[0]) % 360.0, float(дуга[1]) % 360.0
    # ПРИКРАСА НЕСЕ ТОН ВСТАВКОЮ (рядок 1480): колір запису прикраси — слово металу, а емаль чи
    # камінь — виміряні кластери кадру поза металом (`фід_збагачення.колір_вставки`); їх
    # судить та сама точка з допуском виміру, що й вимір речі
    for в in ((x.get("колір_вставки") or ()) if isinstance(x, dict) else ()):
        lab = в.get("lab")
        if lab and not нейтраль(tuple(lab)):
            _L, Cc, h = lch(tuple(lab))
            д = допуск_тону(Cc)
            if _на_дузі(h % 360.0, ((lo - д) % 360.0, (hi + д) % 360.0)):
                return "вимір"
    нв = не_вимір(x)
    if нв is None:
        lab = x.get("lab") if isinstance(x, dict) else None
        if not lab and isinstance(x, dict) and x.get("hex"):
            lab = hx(x["hex"])
        if not lab or нейтраль(tuple(lab)):
            return None
        _L, Cc, h = lch(tuple(lab))
        д = допуск_тону(Cc)
        return "вимір" if _на_дузі(h % 360.0, ((lo - д) % 360.0, (hi + д) % 360.0)) else None
    м = межі_кольору(x)
    if м is None or м[4] is None:
        return None
    # СЛОВО МУСИТЬ НАЗИВАТИ КОЛІР, А НЕ НЕЙТРАЛЬ: центр вікна — представник слова,
    # яким річ стоїть у пулі й яким її судить `palettes.обіцянка_схеми`. Без цієї умови
    # «коричневий» (центр — тепла нейтраль, край вікна C* 45) рахувався б тоном карих
    # очей на 408 речах, а суд образу тієї самої речі казав би «увесь нейтральний».
    lab = x.get("lab") if isinstance(x, dict) else None
    if not lab or нейтраль(tuple(lab)):
        return None
    дс = м[4]
    ширина = (hi - lo) % 360.0 or 360.0
    тони = [(lo + min(k, ширина)) % 360.0 for k in range(int(ширина) + 1)]
    тони += [k % 360.0 for k in дс if _на_дузі(k % 360.0, (lo, hi))]   # вузьке вікно між градусами
    return "слово" if any(_на_дузі(h, дс) for h in тони) else None


def частка_тону(x, дуга):
    """Яка частка тону речі лежить у дузі схеми (0…1) — ранг носіїв тону (рядок 162).

    Вимір у дузі (з допуском) — 1.0. Колір-слово — частка ДУГИ вікна слова, що лежить
    усередині дуги схеми (крок 1°): «м'ятний» (120–190°) під дугою очей 160–184° —
    0.34, «зелений» (100–180°) — 0.25. Річ, що тону не несе (`несе_тон` → None), — 0."""
    як = несе_тон(x, дуга)
    if як is None:
        return 0.0
    if як == "вимір":
        return 1.0
    дс = межі_кольору(x)[4]
    lo, hi = float(дуга[0]) % 360.0, float(дуга[1]) % 360.0
    ширина = (float(дс[1]) - float(дс[0])) % 360.0 or 360.0
    тони = [(float(дс[0]) + k + 0.5) % 360.0 for k in range(int(ширина))] or [float(дс[0]) % 360.0]
    return round(sum(1 for h in тони if _на_дузі(h, (lo, hi))) / len(тони), 3)


def назва_коротко(назва, межа=40):
    """Назва речі для рядка людині: ціла, коли коротка; інакше обрізана ПО МЕЖІ СЛОВА з «…»."""
    н = str(назва or "").strip()
    if len(н) <= межа:
        return н
    зріз = н[:межа].rsplit(" ", 1)[0].rstrip(",;:—-(")
    return (зріз or н[:межа]) + "…"


def _слово_кольору(x):
    """Коротко, чим є колір речі, для рядка людині: «центр вікна слова «X»» чи «вимір»."""
    нв = не_вимір(x)
    if нв is None:
        return "вимір"
    if нв.get("свідок") == "hex моделі":
        return "hex, названий моделлю до слова «%s»" % нв.get("слово")
    return "центр вікна слова «%s»" % нв.get("слово")


