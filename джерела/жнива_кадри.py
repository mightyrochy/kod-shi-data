ЧЕРГА_WOO = os.path.join(ТУТ, "..", "zhnyvarka", "черга_ноутбука_5697.tsv")
_ПОВТОР = ("не скачалось", "сухий прогін", "не встиг")


def відбиток_кадру(url):
    """(файл, query) адреси кадру: однаковий відбиток — той самий знімок, мірити заново нічого."""
    from urllib.parse import urlparse
    return _файл_фото(url), urlparse(url).query


def чому_мірити(старий, url, лічба_з_кольором):
    """Причина виміряти кадр `url` (нова, змінений, повтор, без_класу) або None.

    `старий` — запис цього файла в `каталог_кадри` чи None; `лічба_з_кольором` — скільки
    кадрів речі мають колір (клас ставить аркуш, а на одну плитку аркуша нема)."""
    if not старий:
        return "новий"
    if відбиток_кадру(старий.get("url") or "") != відбиток_кадру(url):
        return "змінений"
    чому = старий.get("чому") or ""
    if старий.get("не_встиг") or старий.get("маска") == "чекає_sam" or any(чому.startswith(п) for п in _ПОВТОР):
        return "повтор"
    if старий.get("lab") and not старий.get("клас") and лічба_з_кольором >= 2:
        return "без_класу"
    return None


def черга_галерей(offers, зб, кадри, сп, хости, інший_колір=(), woo=()):
    """[(офер, збагачення чи None, {файл: причина}, пріоритет)] — що ноутбуку міряти в галереях.

    Пріоритет: 0 — картка «інший_колір» (заява на картці), 1 — варіанти з черги адаптера Woo,
    2 — решта з кадром жнив (якір є), 3 — без кадру жнив (якоря нема, групи без якоря).
    Кадр жнив у чергу не йде: його колір уже в збагаченні."""
    вих = []
    for o in offers:
        ід = o.get("id")
        з = зб.get(ід)
        з = з if _збагачення_придатне(з) and not чужий_кадр(з.get("фото"), сп.get(o.get("магазин")) or {}) else None
        адреси, _ = _адреси_речі(o, з, сп, хости, None)
        старі = {в.get("файл"): в for в in кадри.get(ід) or ()}
        з_кольором = sum(1 for в in старі.values() if в.get("lab"))
        треба = {}
        for u in адреси:
            причина = чому_мірити(старі.get(_файл_фото(u)), u, з_кольором)
            if причина:
                треба[_файл_фото(u)] = причина
        if треба:
            вих.append((o, з, треба, 0 if ід in інший_колір else 1 if ід in woo else 2 if з else 3))
    вих.sort(key=lambda т: т[3])
    return вих


def читати_чергу_woo(шлях=ЧЕРГА_WOO):
    """Множина ід варіантів з черги адаптера Woo (`zhnyvarka/черга_ноутбука_5697.tsv`); нема файла — порожня."""
    if not os.path.exists(шлях):
        return set()
    with open(шлях, encoding="utf-8") as f:
        return {р.split("\t")[0] for р in list(f)[1:] if р.strip()}


def писати_чергу(черга, шлях):
    """TSV черги для запускача: ід, магазин, кадрів, причини (скільки якої), пріоритет."""
    with open(шлях, "w", encoding="utf-8", newline="\n") as f:
        f.write("ід\tмагазин\tкадрів\tпричини\tпріоритет\n")
        for o, _, треба, пр in черга:
            ч = ",".join("%s=%d" % (к, n) for к, n in sorted(collections.Counter(треба.values()).items()))
            f.write("%s\t%s\t%d\t%s\t%d\n" % (o["id"], o.get("магазин") or "", len(треба), ч, пр))


_ЗАМОВЛЕНІ, _замок_замовлень = set(), threading.Lock()


def _адреси_речі(o, з, сп, хости, кадрів, лише=None):
    """(адреси кадрів картки без кадру жнив, префікс файла кадру) — те саме й для виміру,
    і для замовляння наперед, тому лежить окремо. `кадрів` None — уся галерея; `лише` —
    множина файлів (`_файл_фото`), якими обмежити (черга галерей: лише нове й змінене)."""
    мг = o.get("магазин") or str(o.get("id") or "").split("@")[-1]
    файл_жнив = _файл_фото(з.get("фото")) if з else None
    адреси = [u for u in кадри_речі(o, сп.get(мг) or {}, хости, (з or {}).get("фото"))
              if _файл_фото(u) != файл_жнив and (лише is None or _файл_фото(u) in лише)][:кадрів]
    return адреси, "kadry-%s-" % hashlib.md5(o["id"].encode("utf-8")).hexdigest()[:10]


def замовити_наперед(речі, сп, хости, кадрів, качалок, кеш, лише_за_ід=None):
    """Кадри найближчих речей — у пул ЗАРАЗ, щоб вони качалися, доки міряється поточна.

    ЧОМУ ЦЕ, А НЕ БІЛЬШЕ ПОТОКІВ (наряд Н-6, 27.09.2026). `--качалок` — це потоки на
    кадри ОДНІЄЇ речі, а речі більше за `--кадрів` (6) кадрів не буває, тож самим
    `--качалок 32` одночасних кадрів не стане більше за шість: код чекає річ, перш ніж
    узяти наступну. Одночасність дають РЕЧІ В РОБОТІ, а не потоки на річ. Кожна адреса
    замовляється раз (`_ЗАМОВЛЕНІ`): вікно замовлянь сунеться і та сама річ потрапляє в
    нього кілька разів.
    """
    if not кеш:                       # без кеша кадр по речі стирається, замовляти марно
        return 0
    нових = 0
    for o, з in речі:
        адреси, префікс = _адреси_речі(o, з, сп, хости, кадрів, (лише_за_ід or {}).get(o["id"]))
        for u in адреси:
            with _замок_замовлень:
                якщо_нова = u not in _ЗАМОВЛЕНІ
                if якщо_нова:
                    _ЗАМОВЛЕНІ.add(u)
            if якщо_нова:
                _пул(качалок).submit(взяти_кадр, u, префікс, кеш)
                нових += 1
    return нових


def _шматки_аркушів(плитки, на_аркуш=6):
    """Плитки галереї → аркуші не більше `на_аркуш`, порівну (7 → 4+3, а не 6+1: аркуш на
    одну плитку не питають, і самітниця лишилась би без класу). Одна плитка — без аркуша."""
    n = len(плитки)
    if n < 2:
        return []
    k = -(-n // на_аркуш)
    розмір, зайві = divmod(n, k)
    вих, поч = [], 0
    for і in range(k):
        кін = поч + розмір + (1 if і < зайві else 0)
        вих.append(плитки[поч:кін])
        поч = кін
    return вих


def виміряти_річ(o, з, сп, хости, кадрів, сухо, качалок, модель, кеш=False, тайм_кадру=0, лише=None):
    """Кадри картки речі без кадру жнив → [вимір кадру] (див. докстрінг модуля).

    КЛАС ПЛИТКИ (`клас`) — той самий контактний аркуш, що обирає кадр жнив
    (`жнива_запис.обрати_кадр`, один запит на річ): ціла_річ, на_моделі, деталь, підошва,
    етикетка, упаковка, інша_річ, порожня. Без нього першою на картку могла б стати
    підкладка чи бирка потрібного кольору (bella-bicchi ж-08474: 2-й кадр — сіра підкладка),
    а до свідків кольору — чужа річ із галереї (bella-bicchi ж-04890: чотири капелюхи в
    галереї куртки). `модель` None — аркуша нема, клас не пишеться."""
    адреси, префікс = _адреси_речі(o, з, сп, хости, кадрів, лише)
    # ПРЕФІКС ЦІЛКОМ ЛАТИНКОЮ, і хеш id, а не сам id: `cv2.imread` на Windows
    # відкриває файл ANSI-викликом і кириличного шляху не бачить — а це саме ІМ'Я
    # файла, не лише тека. Слово «кадри-» в префіксі давало
    # «NoneType has no attribute shape» на ПЕРШОМУ ж кадрі кожної речі
    # (`жнива_маски.маска_atr`, `cv2.imread` → None), тобто вимір маскою тут не
    # працював ніколи: у PR #391 його перевіряли підробним виміром, який файла не
    # читає. Той самий урок і той самий прийом, що в `жнива_фото.взяти_фото`
    # (там 114 збоїв зі 114 спроб на id речі в імені).
    os.makedirs(КЕШ, exist_ok=True)
    if тайм_кадру:
        # стеля на КАДРИ РЕЧІ: що встигло — міряємо, що ні — лишаємо качатися в пулі
        # й помічаємо `не_встиг`, щоб `main` поклав річ у чергу повтору на кінець
        ф_у = {_пул(качалок).submit(взяти_кадр, u, префікс, кеш): u for u in dict.fromkeys(адреси)}
        _чекати(list(ф_у), timeout=тайм_кадру)
        готове = {}
        for ф, u in ф_у.items():
            if not ф.done():
                continue
            try:
                готове[u] = ф.result()
            except Exception as e:                      # збій качання — як і доти, запис без lab
                готове[u] = {"помилка": "%s: %s" % (type(e).__name__, str(e)[:60])}
        фото = [готове.get(u) or {"помилка": "не встиг за %.0f с" % тайм_кадру, "не_встиг": True}
                for u in адреси]
    else:
        with ThreadPoolExecutor(качалок) as ex:
            фото = list(ex.map(lambda u: взяти_кадр(u, префікс, кеш), адреси))
    тип, слот = тип_речі(o)
    вих, плитки = [], []
    for u, ф in zip(адреси, фото):
        в = dict(файл=_файл_фото(u), url=u)
        if ф.get("з_кешу"):
            в["з_кешу"] = True
        if ф.get("не_встиг"):
            в["не_встиг"] = True
        if ф.get("помилка") or not ф.get("шлях"):
            в["чому"] = "не скачалось: %s" % (ф.get("помилка") or "шляху нема")
        elif ф.get("мала") or ф.get("майже_біла"):
            в["чому"] = "заглушка: %s" % ("менша за 6 КБ" if ф.get("мала") else "майже біла")
        elif сухо:
            в["чому"] = "сухий прогін: маску не кликали"
        else:
            частка, кластери, чому, джерело, _ = виміряти_фото(ф["шлях"], слот)
            в.update(маска=джерело, частка_маски=частка, чому=str(чому)[:160])
            if кластери:
                г = кластери[0]
                в.update(lab=г["lab"], слово=г["слово"], частка=г["частка"], hex=г["hex"],
                         кластери=[[к["слово"], к["частка"], к["hex"]] for к in кластери[:3]])
            плитки.append((в, ф))
        вих.append(в)
    if модель and len(плитки) >= 2:
        for шматок in _шматки_аркушів(плитки):
            _, _, класи, _ = обрати_кадр([ф for _, ф in шматок], тип, слот, модель)
            for н, (в, _) in enumerate(шматок, 1):
                if класи.get(str(н)):
                    в["клас"] = класи[str(н)]
    # кадр із кешу лишається на диску: наступний крок (вимір маскою) бере його звідти
    for ф in фото:
        if not кеш and ф.get("шлях") and os.path.exists(ф["шлях"]):
            os.remove(ф["шлях"])
    return вих


def записати(шлях, дані):
    """gzip JSON атомарно: тимчасовий файл поруч і `os.replace` — обрив не лишає битого файла."""
    тимч = шлях + ".tmp"
    with gzip.open(тимч, "wt", encoding="utf-8") as f:
        json.dump(дані, f, ensure_ascii=False)
    os.replace(тимч, шлях)


