# -*- coding: utf-8 -*-
"""ЖНИВА КАДРІВ — колір КОЖНОГО кадру галереї речі, тим самим виміром, що й кадр жнив v2
(маска ATR → SAM, k-means у Lab — `жнива_колір.виміряти_фото`), для речей, у яких кадр
картки показує інший колір, ніж колір речі (рядок 142, наряд Ф-142).

НАВІЩО. `фід_кадр_колір` ставить на картку першим кадр кольору речі і судить колір речі
кількома кадрами (≥ 2 кадри, згода ≥ 0.9, ПЕРЕДАЧА §5), але колір кадру міряє лише модель
зору (маска речі), а вона на ноутбуці. Без цього виміру рішення бачить один кадр — кадр
жнив, — і на картці лишається заява «на знімку інший колір» (1 108 речей на
каталог_повний, 27.09.2026).

ЩО РОБИТЬ. Читає фід і збагачення, кличе `фід_кадр_колір.рішення` для кожної речі й бере ті,
що мають стан «інший_колір». Для кожної качає кадри картки в порядку `фід_фото.кадри_речі`
(до `--кадрів`, без кадру жнив — його колір уже виміряно), міряє кожен маскою слота речі й
пише в `каталог_кадри.json.gz` поруч (атомарно, кожні `--кожні` речей):
    {"мета": {...}, "записи": {id: [{файл, url, lab, слово, частка, hex, кластери,
                                     маска, частка_маски, чому, клас}]}}
Кадр без маски (SAM сказав «речі нема») пишеться без `lab` і рішення його не бачить.
Код рішення нічого не питає в мережі й моделі: він лише читає цей файл.

ЗАПУСК (ноутбук, тека `джерела`; ATR з Open Source Stylist і ComfyUI з SAM — як у жнивах v2):
    python жнива_кадри.py                                  # усі «інший_колір», по 6 кадрів
    python жнива_кадри.py --крамниці wearme.ua,maxa.ua --ліміт 50
    python жнива_кадри.py --продовжити                     # пропустити вже виміряні
    python жнива_кадри.py --сухо --ліміт 3                 # без маски: відбір і качання
Час: маска ~3 с на кадр (виміряно на вибірці v2, `жнива_маски.маска_речі`) і один запит
аркуша на річ, тобто 1 108 речей × ~5 кадрів ≈ 5–6 год (`--крамниці`/`--ліміт` — частинами,
`--продовжити` — з місця обриву). Після прогону: закомітити `каталог_кадри.json.gz` і
перезапустити `проби/foto_kolir_142.py` — вона друкує, скільки карток дістали свій кадр.

РЕБРА. Імпортує `feed` (фід, збагачення), `фід_фото` (кадри картки), `фід_кадр_колір`
(відбір і ім'я файла), `жнива_фото` (качання — той самий шлях, що в жнивах), `жнива_колір`
(вимір), `жнива_промпти.тип_речі` (слот маски), `жнива_запис.обрати_кадр` (клас плиток
на контактному аркуші — один запит до qwen3-vl на річ), `жнива_прогін._не_спати` (Windows)."""
import argparse, gzip, hashlib, json, os, sys, threading, time
from concurrent.futures import ThreadPoolExecutor
import feed as F
import фід_кадр_колір as ФКК
from фід_фото import кадри_речі, _файл_фото, _спільні_фото, _хости_крамниць, чужий_кадр
from фід_збагачення import _збагачення_придатне
from жнива_фото import _скачати_фото, збільшити_url
from жнива_реєстр import КЕШ
from жнива_колір import виміряти_фото
from жнива_промпти import тип_речі
from жнива_запис import обрати_кадр
from жнива_прогін import _не_спати

ТУТ = os.path.dirname(os.path.abspath(__file__)) or "."
ВИХІД = os.path.join(ТУТ, ФКК.КАДРИ_ІМ + ".gz")


# ── КЕШ КАДРІВ НА ДИСКУ (`--кеш`, наряд Н-4, 27.09.2026) ─────────────────────
# ЧОМУ. На ноутбуці качання одного кадру коштує 5–40 с (виміряно 27.09 на кадрах
# wearme: 54 КБ/с в один потік, 167 КБ/с на 12 потоків; кадр збільшеної адреси —
# 0.6–1.2 МБ), а маска — ~3 с. Тобто без кешу прогін чекає на мережу довше, ніж
# рахує, і GPU стоїть. `--кеш` розділяє качання і вимір на два кроки: `--сухо
# --кеш` набиває диск (лише мережа, GPU вільна для іншої сесії), а прогін з
# маскою з тим самим `--кеш` бере ті самі кадри з диска.
# ЧОМУ В ІНДЕКСІ ЛЕЖИТЬ ВІДПОВІДЬ, А НЕ ЛИШЕ ШЛЯХ: `мала` і `байтів` міряють СИРІ
# байти адреси, яких після перезапису кадру в JPEG уже не видно, а `_файл_фото`
# і відсів заглушок судять по них.
ІНДЕКС = os.path.join(КЕШ, "кадри_індекс.json")
_індекс, _замок_індексу, _мій_індекс = {}, threading.Lock(), ІНДЕКС


def _прочитати_індекс():
    """Індекс кешу з диска (раз на процес): ЧИТАЮТЬСЯ ВСІ `кадри_індекс*.json`,
    ПИШЕТЬСЯ лише свій (`--кеш-індекс`). Чому так: мережа тут вузька (виміряно
    27.09: 338 кадрів/год в одному прогоні), тож качають кілька процесів по різних
    крамницях водночас, а спільний один файл вони затирали б один одному —
    останній запис вигравав би, і кадри на диску ставали б невидимі.
    Битий файл — порожній, але з друком, не мовчки (п.14)."""
    import glob as _glob
    for ш in sorted(_glob.glob(os.path.join(КЕШ, "кадри_індекс*.json"))):
        try:
            with open(ш, encoding="utf-8") as f:
                _індекс.update(json.load(f))
        except Exception as e:
            print("індекс %s не прочитано (%s) — ті кадри качаємо заново" % (os.path.basename(ш), e))
    if _індекс:
        print("кеш кадрів: %d адрес на диску" % len(_індекс))
    _свій.update(_індекс)


_свій = {}   # що записав САМЕ цей процес (+ прочитане на старті): те й лягає у свій файл


def записати_індекс():
    """Свій індекс на диск атомарно: обрив прогону не губить уже скачаного."""
    with _замок_індексу:
        дані = dict(_свій)
    тимч = _мій_індекс + ".tmp"
    with open(тимч, "w", encoding="utf-8") as f:
        json.dump(дані, f, ensure_ascii=False)
    os.replace(тимч, _мій_індекс)


def взяти_кадр(u, префікс, кеш):
    """Кадр адреси: з диска, коли його вже качали, інакше з мережі (і в кеш).
    Ключ — md5 АДРЕСИ (хеша байтів до качання ніхто не знає)."""
    ключ = hashlib.md5(u.encode("utf-8")).hexdigest()
    if кеш:
        з = _індекс.get(ключ)
        if з and з.get("шлях") and os.path.exists(з["шлях"]):
            return dict(з, з_кешу=True)
    зап = _скачати_фото(u, збільшити_url(u), префікс)
    if кеш and зап.get("шлях"):
        with _замок_індексу:
            _індекс[ключ] = зап
            _свій[ключ] = зап
    return зап


def цілі(offers, зб):
    """[(офер, збагачення)] речей, чий кадр картки показує інший колір, а свого кадру код не знає."""
    сп = _спільні_фото(offers)
    к = ФКК.контекст(offers, зб, сп)
    вих = []
    for o in offers:
        з = зб.get(o.get("id"))
        if not _збагачення_придатне(з) or чужий_кадр(з.get("фото"), сп.get(o.get("магазин")) or {}):
            continue
        if ФКК.рішення(o, з, к)["стан"] == "інший_колір":
            вих.append((o, з))
    return вих, сп


def виміряти_річ(o, з, сп, хости, кадрів, сухо, качалок, модель, кеш=False):
    """Кадри картки речі без кадру жнив → [вимір кадру] (див. докстрінг модуля).

    КЛАС ПЛИТКИ (`клас`) — той самий контактний аркуш, що обирає кадр жнив
    (`жнива_запис.обрати_кадр`, один запит на річ): ціла_річ, на_моделі, деталь, підошва,
    етикетка, упаковка, інша_річ, порожня. Без нього першою на картку могла б стати
    підкладка чи бирка потрібного кольору (bella-bicchi ж-08474: 2-й кадр — сіра підкладка),
    а до свідків кольору — чужа річ із галереї (bella-bicchi ж-04890: чотири капелюхи в
    галереї куртки). `модель` None — аркуша нема, клас не пишеться."""
    мг = o.get("магазин") or str(o.get("id") or "").split("@")[-1]
    файл_жнив = _файл_фото(з.get("фото"))
    адреси = [u for u in кадри_речі(o, сп.get(мг) or {}, хости, з.get("фото"))
              if _файл_фото(u) != файл_жнив][:кадрів]
    # префікс — хеш id, а не сам id: `cv2.imread` на Windows не бачить кириличного шляху
    # (той самий прийом, що в `жнива_фото.взяти_фото`)
    префікс = "кадри-%s-" % hashlib.md5(o["id"].encode("utf-8")).hexdigest()[:10]
    os.makedirs(КЕШ, exist_ok=True)
    with ThreadPoolExecutor(качалок) as ex:
        фото = list(ex.map(lambda u: взяти_кадр(u, префікс, кеш), адреси))
    тип, слот = тип_речі(o)
    вих, плитки = [], []
    for u, ф in zip(адреси, фото):
        в = dict(файл=_файл_фото(u), url=u)
        if ф.get("з_кешу"):
            в["з_кешу"] = True
        if ф.get("помилка") or not ф.get("шлях"):
            в["чому"] = "не скачалось: %s" % (ф.get("помилка") or "шляху нема")
        elif ф.get("мала") or ф.get("майже_біла"):
            в["чому"] = "заглушка: %s" % ("менша за 6 КБ" if ф.get("мала") else "майже біла")
        elif сухо:
            в["чому"] = "сухий прогін: маску не кликали"
        else:
            частка, кластери, чому, джерело, _ = виміряти_фото(ф["шлях"], слот)
            в.update(маска=джерело, частка_маски=частка, чому=str(чому)[:160])
            if кластери:
                г = кластери[0]
                в.update(lab=г["lab"], слово=г["слово"], частка=г["частка"], hex=г["hex"],
                         кластери=[[к["слово"], к["частка"], к["hex"]] for к in кластери[:3]])
            плитки.append((в, ф))
        вих.append(в)
    if модель and len(плитки) >= 2:
        # аркуш бере не більше шести плиток — рівно стільки, скільки кадрів тут за замовчуванням
        _, _, класи, _ = обрати_кадр([ф for _, ф in плитки[:6]], тип, слот, модель)
        for н, (в, _) in enumerate(плитки[:6], 1):
            if класи.get(str(н)):
                в["клас"] = класи[str(н)]
    # кадр із кешу лишається на диску: наступний крок (вимір маскою) бере його звідти
    for ф in фото:
        if not кеш and ф.get("шлях") and os.path.exists(ф["шлях"]):
            os.remove(ф["шлях"])
    return вих


def записати(шлях, дані):
    """gzip JSON атомарно: тимчасовий файл поруч і `os.replace` — обрив не лишає битого файла."""
    тимч = шлях + ".tmp"
    with gzip.open(тимч, "wt", encoding="utf-8") as f:
        json.dump(дані, f, ensure_ascii=False)
    os.replace(тимч, шлях)


def main():
    """Аргументи, відбір, вимір, запис; друкує поступ і підсумок."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--кадрів", type=int, default=6, help="скільки кадрів речі міряти (без кадру жнив)")
    ap.add_argument("--крамниці", default="", help="лише ці крамниці, через кому")
    ap.add_argument("--ліміт", type=int, default=None, help="лише перші N речей")
    ap.add_argument("--продовжити", action="store_true", help="пропустити речі, уже записані у вихід")
    ap.add_argument("--заново", action="store_true", help="почати порожній вихід (інакше наявний дописується)")
    ap.add_argument("--сухо", action="store_true", help="без маски: відбір і качання (перевірка шляху)")
    ap.add_argument("--кеш", action="store_true",
                    help="кадри лишати на диску й брати звідти (качання окремим кроком від виміру)")
    ap.add_argument("--качалок", type=int, default=6, help="потоків качання кадрів однієї речі")
    ap.add_argument("--кожні", type=int, default=20, help="записувати вихід кожні N речей")
    ap.add_argument("--частка", default="", metavar="N/M",
                    help="узяти лише кожну M-ту річ зі зсувом N (0-based): паралельні "
                         "качалки на різних частках однієї черги, без поділу за крамницями")
    ap.add_argument("--кеш-індекс", default=ІНДЕКС,
                    help="свій файл індексу кешу (паралельні качалки — різні файли)")
    ap.add_argument("--вихід", default=ВИХІД)
    ap.add_argument("--модель", default="qwen3-vl-8b-instruct", help="модель аркуша (LM Studio), як у жнивах v2")
    ap.add_argument("--без-аркуша", action="store_true", help="не питати модель класу плиток")
    а = ap.parse_args()
    offers = F.читати_yml(F.каталог_на_диску())[0]
    зб = F.читати_збагачення()
    сп_цілі, сп = цілі(offers, зб)
    крамниці = {к.strip() for к in а.крамниці.split(",") if к.strip()}
    # наявний вихід ДОПИСУЄТЬСЯ, а не затирається: прогін частинами (`--крамниці`, `--ліміт`)
    # без `--продовжити` лише переміряє свої речі, а чужі лишає; порожній — лише `--заново`
    дані = {"мета": {}, "записи": {}}
    if os.path.exists(а.вихід) and not а.заново:
        with gzip.open(а.вихід, "rt", encoding="utf-8") as f:
            дані = json.load(f)
    черга = [(o, з) for o, з in сп_цілі
             if (not крамниці or o.get("магазин") in крамниці)
             and not (а.продовжити and o["id"] in дані["записи"])]
    if а.частка:
        # частка береться ПІСЛЯ відбору й ДО ліміту: кожна качалка бачить ту саму
        # чергу в тому самому порядку, тож частки не перетинаються і разом дають усе
        зсув, скільки = (int(ч) for ч in а.частка.split("/"))
        черга = [п for н, п in enumerate(черга) if н % скільки == зсув]
    черга = черга[:а.ліміт]
    print("речей з кадром іншого кольору: %d; у черзі: %d; вихід: %s" % (len(сп_цілі), len(черга), а.вихід))
    if а.кеш:
        global _мій_індекс
        _мій_індекс = а.кеш_індекс
        _прочитати_індекс()
    хости, т0 = _хости_крамниць(offers), time.time()
    _не_спати()
    try:
        for і, (o, з) in enumerate(черга, 1):
            т = time.time()
            дані["записи"][o["id"]] = виміряти_річ(o, з, сп, хости, а.кадрів, а.сухо, а.качалок,
                                                    None if (а.сухо or а.без_аркуша) else а.модель, а.кеш)
            print("[%d/%d] %s: кадрів %d, з кольором %d, з кешу %d, %.1f с" % (
                і, len(черга), o["id"], len(дані["записи"][o["id"]]),
                sum(1 for в in дані["записи"][o["id"]] if в.get("lab")),
                sum(1 for в in дані["записи"][o["id"]] if в.get("з_кешу")), time.time() - т))
            if і % а.кожні == 0 or і == len(черга):
                дані["мета"] = dict(знято=time.strftime("%Y-%m-%d"), маска="жнива_маски.маска_речі (ATR → SAM)",
                                    аркуш=(None if (а.сухо or а.без_аркуша) else а.модель),
                                    кадрів_на_річ=а.кадрів, записів=len(дані["записи"]), сухо=а.сухо,
                                    кадрів=sum(len(в) for в in дані["записи"].values()))
                записати(а.вихід, дані)
                if а.кеш:
                    записати_індекс()
    finally:
        _не_спати(вимкнути=True)
    print("готово за %.0f хв: %s" % ((time.time() - т0) / 60, json.dumps(дані["мета"], ensure_ascii=False)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
