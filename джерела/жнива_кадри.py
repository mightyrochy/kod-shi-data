# ── КЕШ КАДРІВ НА ДИСКУ (`--кеш`, наряд Н-4, 27.09.2026) ─────────────────────
# ЧОМУ. На ноутбуці качання одного кадру коштує 5–40 с (виміряно 27.09 на кадрах
# wearme: 54 КБ/с в один потік, 167 КБ/с на 12 потоків; кадр збільшеної адреси —
# 0.6–1.2 МБ), а маска — ~3 с. Тобто без кешу прогін чекає на мережу довше, ніж
# рахує, і GPU стоїть. `--кеш` розділяє качання і вимір на два кроки: `--сухо
# --кеш` набиває диск (лише мережа, GPU вільна для іншої сесії), а прогін з
# маскою з тим самим `--кеш` бере ті самі кадри з диска.
# ЧОМУ В ІНДЕКСІ ЛЕЖИТЬ ВІДПОВІДЬ, А НЕ ЛИШЕ ШЛЯХ: `мала` і `байтів` міряють СИРІ
# байти адреси, яких після перезапису кадру в JPEG уже не видно, а `_файл_фото`
