ІНДЕКС = os.path.join(КЕШ, "кадри_індекс.json")
_індекс, _замок_індексу, _мій_індекс = {}, threading.Lock(), ІНДЕКС


def _прочитати_індекс():
    """Індекс кешу з диска (раз на процес): ЧИТАЮТЬСЯ ВСІ `кадри_індекс*.json`,
    ПИШЕТЬСЯ лише свій (`--кеш-індекс`). Чому так: мережа тут вузька (виміряно
    27.09: 338 кадрів/год в одному прогоні), тож качають кілька процесів по різних
    крамницях водночас, а спільний один файл вони затирали б один одному —
    останній запис вигравав би, і кадри на диску ставали б невидимі.
    Битий файл — порожній, але з друком, не мовчки (п.14)."""
    import glob as _glob
    for ш in sorted(_glob.glob(os.path.join(КЕШ, "кадри_індекс*.json"))):
        try:
            with open(ш, encoding="utf-8") as f:
                _індекс.update(json.load(f))
        except Exception as e:
            print("індекс %s не прочитано (%s) — ті кадри качаємо заново" % (os.path.basename(ш), e))
    if _індекс:
        print("кеш кадрів: %d адрес на диску" % len(_індекс))
    _свій.update(_індекс)


_свій = {}   # що записав САМЕ цей процес (+ прочитане на старті): те й лягає у свій файл


def записати_індекс():
    """Свій індекс на диск атомарно: обрив прогону не губить уже скачаного."""
    with _замок_індексу:
        дані = dict(_свій)
    тимч = _мій_індекс + ".tmp"
    with open(тимч, "w", encoding="utf-8") as f:
        json.dump(дані, f, ensure_ascii=False)
    os.replace(тимч, _мій_індекс)


# ── СПІЛЬНИЙ ПУЛ КАЧАННЯ (`--тайм-кадру`, наряд Н-6, 27.09.2026) ─────────────
# ЧОМУ. `виміряти_річ` качало кадри речі через `with ThreadPoolExecutor(...)`, а вихід
# із цього `with` чекає КОЖЕН потік. Тому річ коштувала стільки, скільки її
# НАЙПОВІЛЬНІШИЙ кадр: виміряно 27.09 на 12 кадрах — поодинокі кадри йдуть 200–640
# КБ/с, але один упав у TimeoutError на 85.8 с, другий тягнувся 128.4 с, і разом
# вийшло 63 КБ/с. Смуга тут не винна, винне чекання.
# ЯК. Пул живе довше за річ: кадр-тугодум лишається в ньому качатися й після того, як
# річ пішла далі, а докачавшись — лягає в кеш. Воркерів більше за `качалок` саме тому,
# що покинуті кадри тримають слоти.
_ПУЛ, _замок_пулу = None, threading.Lock()


def _пул(качалок):
    """Один пул качання на процес: покинутий кадр докачується в ньому, не тримаючи річ."""
    global _ПУЛ
    with _замок_пулу:
        if _ПУЛ is None:
            _ПУЛ = ThreadPoolExecutor(max_workers=качалок * 4, thread_name_prefix="kadry")
        return _ПУЛ


def взяти_кадр(u, префікс, кеш):
    """Кадр адреси: з диска, коли його вже качали, інакше з мережі (і в кеш).
    Ключ — md5 АДРЕСИ (хеша байтів до качання ніхто не знає)."""
    ключ = hashlib.md5(u.encode("utf-8")).hexdigest()
    if кеш:
        з = _індекс.get(ключ)
        if з and з.get("шлях") and os.path.exists(з["шлях"]):
            return dict(з, з_кешу=True)
    зап = _скачати_фото(u, збільшити_url(u), префікс)
    if кеш and зап.get("шлях"):
        with _замок_індексу:
            _індекс[ключ] = зап
            _свій[ключ] = зап
    return зап


def аркуш_речі(o, записи, модель):
    """Клас КОЖНОГО виміряного кадру речі з контактного аркуша — БЕЗ переміру маски.

    ЧОМУ ОКРЕМИЙ ХІД (наряд Н-6, 27.09.2026). `виміряти_річ` переписує запис речі
    ЦІЛКОМ, тож прогін «лише аркуш» після прогону з SAM затер би виміри SAM, а прогін
    із SAM і аркушем разом тримав би на карті дві моделі водночас (ComfyUI із SAM і
    qwen3-vl у LM Studio) — саме те, від чого карта вже клякла. Цей хід бере кадри з
    КЕША за адресою (вимір уже пройшов) і дописує лише `клас`, нічого не переміряючи.
    Повертає, скільком кадрам поставив клас.
    """
    плитки = []
    for в in записи:
        зап = _індекс.get(hashlib.md5(в["url"].encode("utf-8")).hexdigest()) if в.get("url") else None
        if в.get("lab") and зап and зап.get("шлях") and os.path.exists(зап["шлях"]):
            плитки.append((в, зап))
    if len(плитки) < 2:                       # аркуш на одну плитку не потрібен
        return 0
    тип, слот = тип_речі(o)
    поставлено = 0
    for шматок in _шматки_аркушів(плитки):
        _, _, класи, _ = обрати_кадр([ф for _, ф in шматок], тип, слот, модель)
        for н, (в, _) in enumerate(шматок, 1):
            if класи.get(str(н)):
                в["клас"] = класи[str(н)]
                поставлено += 1
    return поставлено


def цілі(offers, зб):
    """[(офер, збагачення)] речей, чий кадр картки показує інший колір, а свого кадру код не знає."""
