# `"weather_band": "мінус десять"`, хоч смуга паспорта правильна. Тепер поле з ознакою `уривок_лише_мові` уривок
# лишає у факті картки (сила й суд речень — як були), а далі неї — ні: плоскої цитати нема (`картка_запиту._проєкція`),
# походження — вид без уривка; стилістка й картка знають лише смугу.
УРИВОК_ЛИШЕ_МОВІ = frozenset(к for к, в in ПОЛЯ_ПАСПОРТА.items() if в.get("уривок_лише_мові"))


def уривок_далі(поле):
    """Чи її уривок поля паспорта йде далі факту картки: плоскою цитатою й у походженні поля (`УРИВОК_ЛИШЕ_МОВІ`)."""
