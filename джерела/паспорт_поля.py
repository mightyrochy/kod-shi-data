def чинний_ключ(поле, значення):
    """Ключ збереженого паспорта → чинний ключ того самого поля."""
    опис = ПОЛЯ_ПАСПОРТА.get(поле, {})
    if not isinstance(значення, str):
        return значення
    return опис.get("старі_ключі", {}).get(значення, значення)


# ── ШЛЯХ ПОЛЯ: СХЕМА → ПАСПОРТ → ВХІД СТИЛІСТКИ — З ОДНОГО ПЕРЕЛІКУ (корінь Е2-втрата-слова, 16.11) ──
# Поле, яке модель розмови пише (`мова`) і яке має код дроту (`поле`), іде стилістці в `case` під тим самим кодом,
# що в схемі відповіді. Доти переліки вели окремо (`протокол.ВИПАДОК`, `дріт_моделі.ПОЛЯ_ВИПАДКУ`), і поле, записане
# в паспорт, до стилістки не доходило: місяць 4 з 4, відкриті зони, схема палітри (лічба 16.11). `дріт_моделі`
# лише перейменовує давні ключі (`refusals`, `wishes`…), а `протокол.ВИПАДОК` бере звідси решту полів. Не їде
# лише поле з причиною в `стилістці` — уривок чи факт, який несе інше поле входу.
def поля_стилістці():
    """{ключ паспорта: код дроту} — усі поля схеми розмови, що йдуть стилістці (`case`)."""
    return {к: в["поле"] for к, в in ПОЛЯ_ПАСПОРТА.items()
            if not к.startswith("@") and в.get("поле") and "мова" in в and "стилістці" not in в}


def перелік_поля(ключ):
    """Перелік кодів поля паспорта (`вимір`/`вісь`) — ним дріт кодує слово ядра; поля без переліку — None."""
    в = ПОЛЯ_ПАСПОРТА.get(ключ) or {}
    вісь = в.get("вимір") or в.get("вісь")
    return вісь[1] if вісь else None


