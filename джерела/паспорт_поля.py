def чинний_ключ(поле, значення):
    """Ключ збереженого паспорта → чинний ключ того самого поля."""
    опис = ПОЛЯ_ПАСПОРТА.get(поле, {})
    if not isinstance(значення, str):
        return значення
    return опис.get("старі_ключі", {}).get(значення, значення)


def поля_виду(ознака):
    """Імена полів паспорта з ознакою виду (її слова вільним текстом, норма ходу плиток, коди норми, поза
    розмовою): булева — у порядку паспорта, число — за числом."""
    знайдені = [(в[ознака], в["поле"]) for в in ПОЛЯ_ПАСПОРТА.values() if "поле" in в and в.get(ознака) is not None]
    return tuple(п for _, п in (знайдені if all(isinstance(з, bool) for з, _ in знайдені) else sorted(знайдені)))


def поля_показу():
    """Серійні метадані полів для бібліотеки, типових чисел і плиток показу."""
    return {к: {п: в[п] for п in ("показ", "плитка", "поле", "старі_ключі", "число", "довідник") if п in в}
            for к, в in ПОЛЯ_ПАСПОРТА.items() if not к.startswith("@")}


# ── ВИД ФАКТУ КАРТКИ ЗАПИТУ: ЇЇ СЛОВО, ТЛУМАЧЕННЯ, РУКА, ТИПОВЕ (п.6–7 класу Е2-межі, рішення менеджера 31.10) ──
# Її факт — лише значення, що дослівно стоїть у її уривку (регістр, апостроф, розділові знаки й пробіли не важать,
# число — цифрами): «о 19», «19:30» — її година; «о сьомій» — тлумачення моделі зі значенням 19 і її уривком; код поля
# (`wedding_guest` на «на весілля») — теж тлумачення з її уривком: уривок доводить, що слова її, а не що вони означають
# цей код. Що слова означають, вирішує лише модель (`аудит/ПРОДУКТ.md`, п.12): код звіряє походження рядків, а форм
# слів, письма й підписів плиток не читає. Звідси беруть вид картка (`картка_запиту.записати`), шар, показ (`політика`)
# і стилістка (`звідки_виміру`).
ЇЇ, ТЛУМАЧЕННЯ, РУКА, ТИПОВЕ = "her", "reading", "hand", "default"
ВИДИ_ФАКТУ = frozenset((ЇЇ, ТЛУМАЧЕННЯ, РУКА, ТИПОВЕ))
# Сила факту: новіший рівносильний перемагає, слабший сильнішого не стирає. Тлумачення з її уривком спирається на її
# слова так само, як її слово, — інакше тлумачення без уривка наступного ходу стирало б його.
СИЛА_ФАКТУ = {ТИПОВЕ: 0, ТЛУМАЧЕННЯ: 1, ЇЇ: 2, РУКА: 2}
СИЛА_З_УРИВКОМ = {ТЛУМАЧЕННЯ: 2}
# Вид факту → звідки вимір для стилістки (`внутрішня_мова`, `evidence_source`): тлумачення — `sub`, не її слова.
_ЗВІДКИ = {ЇЇ: "her_words", РУКА: "her_words", ТЛУМАЧЕННЯ: "sub", ТИПОВЕ: "default"}


def до_звірки(текст):
    """Текст для звірки цитати: нижній регістр, один апостроф, розділові знаки — пробілом."""
    т = str(текст or "").lower().replace("’", "'").replace("ʼ", "'").replace("`", "'")
    return " ".join(re.sub(r"[^\w']+", " ", т).split())


def цитата_тримає(цитата, слова):
    """Чи дослівний уривок `цитата` стоїть у її словах `слова` (регістр, лапки, розділові
    знаки й пробіли не важать). Порожня цитата чи без жодної літери й цифри — не тримає;
    цитата з самих чисел — лише цілими числами («6» не тримається її «16:00»)."""
    ц, т = до_звірки(цитата), до_звірки(слова)
    if not re.search(r"[^\W_]", ц):
        return False
    if not re.search(r"[^\W\d_]", ц):
        return (" %s " % ц) in (" %s " % т)
    return ц in т


def _рядком(значення):
    """Значення факту рядком для звірки: число — цифрами без зайвого «.0»; список — кожен елемент; решта — None."""
    if isinstance(значення, bool):
        return None
    if isinstance(значення, (int, float)):
        return None if значення != значення or значення in (float("inf"), float("-inf")) else \
            ("%d" % значення if float(значення).is_integer() else repr(float(значення)))
    if isinstance(значення, str):
        return значення
    return None


def дослівно(значення, уривок):
    """Чи значення факту дослівно стоїть у її уривку: рядок — як `цитата_тримає`, число — цифрами цілим числом,
    список — кожен елемент; код, смуга, об'єкт — ні (це тлумачення моделі)."""
    if isinstance(значення, (list, tuple)):
        return bool(значення) and all(дослівно(з, уривок) for з in значення)
    р = _рядком(значення)
    return bool(р and str(уривок or "").strip()) and цитата_тримає(р, уривок)


def вид_з_розмови(значення, уривок):
    """Вид факту, який дала розмова: її слово — лише дослівно в її (чинному) уривку, інакше тлумачення моделі."""
    return ЇЇ if дослівно(значення, уривок) else ТЛУМАЧЕННЯ


def сила_факту(факт):
    """Сила факту картки (`СИЛА_ФАКТУ`; тлумачення з її уривком — як її слово); невідомий вид — -1."""
    вид = (факт or {}).get("джерело")
    if (факт or {}).get("уривок") and вид in СИЛА_З_УРИВКОМ:
        return СИЛА_З_УРИВКОМ[вид]
    return СИЛА_ФАКТУ.get(вид, -1)


def на_її_словах(факт):
    """Чи факт спирається на неї: її слово, рука чи тлумачення з її уривком (а не тлумачення без уривка чи типове)."""
    вид = (факт or {}).get("джерело")
    return вид in (ЇЇ, РУКА) or (вид == ТЛУМАЧЕННЯ and bool(str((факт or {}).get("уривок") or "").strip()))


def рукою(факт):
    """Чи факт поставила її рука (подія плитки)."""
    return (факт or {}).get("джерело") == РУКА


def типовий(факт):
    """Чи факт — типове значення коду, а не вона й не модель."""
    return (факт or {}).get("джерело") == ТИПОВЕ


def звідки_виміру(факт):
    """Звідки вимір для стилістки за видом факту: `her_words` (її слово чи рука), `sub` (тлумачення), `default`."""
    return _ЗВІДКИ.get((факт or {}).get("джерело"), "default")
