МАКС_ТОНІВ = 8

def шкіра(d):
    """Шкіра приходить одним hex АБО списком точок (щока, лоб, щелепа).

    ЧОМУ СПИСОК, І ЧОМУ НЕ ТАК, ЯК ВОЛОССЯ. Це РІЗНІ речі, і плутати їх не можна.
    Кілька тонів волосся — ВЛАСТИВІСТЬ людини: мелірування справді несе крок
    світлоти, і цей крок іде в правило. Кілька точок шкіри — не властивість, а
    ПОВТОРНИЙ ЗАМІР однієї величини: обличчя не дає образу «крок світлоти
    задарма». Тому розкид шкіри НІКОЛИ не потрапляє в бриф — він говорить лише
    про якість виміру.

    НАВІЩО ВЗАГАЛІ. Заміряно на трьох профілях: одна точка на щоці несе ±8–14 L*
    похибки від тіні, відблиску й тонального, і на двох профілях із трьох ця
    похибка ПЕРЕКИДАЄ рівень контрасту (середній↔високий, низький↔середній), а
    рівень задає крок світлоти в брифі: 25 проти 45 проти 100 одиниць. Медіана
    трьох точок збила похибку з 8.9 до 1.0 L*.

    Медіана, а не середнє: одна точка в тіні — це викид, і середнє його тягне."""
    ш = d.get("шкіра")
    сп = [ш] if isinstance(ш, str) else [x for x in (ш or []) if x]
    return сп[:6]

def медіана_lab(labs):
    """Покоординатна медіана списку Lab — одна точка з кількох замірів шкіри."""
    import statistics as _st
    if not labs:
        # названа помилка, не `StatisticsError` (дошка 14716): без жодної точки шкіри кольорів профілю нема —
        # викликач, що вміє судити без них, питає `збірка_речі`
        raise ValueError("шкіра: жодної точки — кольорів профілю нема")
    return tuple(_st.median([l[i] for l in labs]) for i in range(3))

def волосся(d, *, без_підстановки=False):
    """Волосся приходить СПИСКОМ довільної довжини. Один hex — законний випадок
    (рівний однотонний колір), а не помилка. Кілька — теж законний: мелірування,
    балаяж, відрослі корені й сивина дають кілька кроків світлоти на голові, і
    outfit.контраст_особи це вміє (збирає всі риси з ключем на «волосся», рахує
    σ і, коли σ > step_min, каже: крок в образі вже є)."""
    в = d.get("волосся")
    сп = [в] if isinstance(в, str) else [x for x in (в or []) if x]
    if без_підстановки:
        return сп[:МАКС_ТОНІВ]
    return сп[:МАКС_ТОНІВ] or [d["шкіра"]]

def зсув_волосся(labs, ціль_L):
    """Ручка світлоти рухає ВСІ пасма на ту саму дельту: інакше виправлення
    середньої світлоти знищило б розкид, тобто ту саму річ, заради якої
    пасма й питаються."""
    if ціль_L is None or not labs:
        return labs
    д = float(ціль_L) - labs[0][0]
    return [(max(3.0, min(97.0, L + д)), a, b) for L, a, b in labs]

ДЖЕРЕЛО_ТИПОВЕ = "model_hex"

def _джерело_кольору(d):
    """Перевіряє походження кольору; без поля це оцінка моделі портрета."""
    дж = d.get("source") or ДЖЕРЕЛО_ТИПОВЕ
    if дж not in cs.AXIS_RELIABILITY:
        raise ValueError("невідоме джерело кольору %r; відомі: %s"
                         % (дж, ", ".join(sorted(cs.AXIS_RELIABILITY))))
    return дж

def вимір_портрета(d):
    """Вимір кадру портрета з входу показу (`портрет_вимір.виміряти`, ключ `портрет_вимір`), коли ворота кадру
    пройдено й є шкіра й волосся; інакше None — діє hex моделі під власним ім'ям (`model_hex`). Очей вимір не несе:
    їхню сім'ю називає модель (`очі_оцінки`)."""
    в = d.get("портрет_вимір")
    if not isinstance(в, dict) or в.get("стан") != "вимір":
        return None
    if not all(isinstance(в.get(к), dict) and в[к].get("lab") for к in ("шкіра", "волосся")):
        return None
    return в

def _features_виміру(d, вим):
    """Риси з виміру кадру: шкіра й волосся — Lab, похибка оцінки (`se_L`, `se_ab`), джерело «uncontrolled» і слід
    виміру з певністю класів (`портрет_вимір.певні`); очі — оцінка моделі під власним ім'ям (`очі_оцінки`). Кільце
    райдужки з hex моделі сюди не домішується: числа риси в профілі виміру — лише виміряні."""
    lab = lambda к: tuple(float(x) for x in вим[к]["lab"])
    точки = [tuple(float(x) for x in т) for т in (вим["шкіра"].get("точки") or [вим["шкіра"]["lab"]])]
    ш = lab("шкіра")
    вл_усі = зсув_волосся([lab("волосся")]
                          + [tuple(float(x) for x in т) for т in (вим["волосся"].get("варіанти_рамки") or [])],
                          d.get("L_волосся"))
    вл, рамка_вл = [вл_усі[0]], вл_усі[1:]
    if d.get("L_шкіра") is not None:
        ш = (float(d["L_шкіра"]), ш[1], ш[2])
    риси = {"шкіра": (ш,) + _похибки(вим["шкіра"]), "волосся": (вл[0],) + _похибки(вим["волосся"])}
    import портрет_вимір as _ПВ
    будувати = lambda в: cs.features(в["шкіра"], в["волосся"], None, джерело=_ПВ.ДЖЕРЕЛО)
    певні = _ПВ.певні(риси, lambda в: _ОЗ.класи(будувати(в), _ПВ.ДЖЕРЕЛО),
                      {"волосся": рамка_вл} if рамка_вл else None)
    F = будувати({р: в[0] for р, в in риси.items()})
    for р, (_, se_L, se_ab) in риси.items():
        F[р].update(se_L=se_L, se_ab=se_ab)
    _очі_моделі(F, d)
    F["_meta"]["protocol"] = _ПВ.ДЖЕРЕЛО
    F["_meta"]["вимір_портрета"] = dict(певні=певні, шум_зон=вим["шкіра"].get("шум_зон"),
                                        n={р: вим[р].get("n") for р in ("шкіра", "волосся")})
    return F, ш, вл, None, точки

def _очі_моделі(F, d):
    """Очі профілю з відповіді моделі зору — оцінка під власним ім'ям (`face_features.покласти_очі`): сім'я кодом
    (`колір_очей`) і hex плитки, без L/a/b. Сім'ї модель не назвала — `код` None, «невідомо», а не типова сім'я."""
    return _ОЗ.покласти_очі(F, d.get("очі"), d.get("колір_очей"))

def _похибки(риса):
    return (float(риса.get("se_L") or 0.0), float(риса.get("se_ab") or 0.0))

def features(d, *, неповний_портрет=False):
    """Риси з входу та їхнє походження: (F, шкіра, пасма, очі, точки шкіри).

    Вимір кадру портрета (`вимір_портрета`) — риси, які зміряв код; без нього — hex моделі зору, оцінка
    (`model_hex`) без протоколу камери. Додані пасма й кільце успадковують спільне походження профілю через `_meta`.
    Очі з портрета — завжди оцінка моделі (`_очі_моделі`): її hex — плитка, сім'я — код моделі; числа очей у профілі
    — лише з її слова (ручний hex, `self_report`). Неповний портрет залишає лише надані риси.
    """
    вим = вимір_портрета(d)
    if вим:
        return _features_виміру(d, вим)
    точки = [cs.hx(x) for x in шкіра(d)]
    ш = медіана_lab(точки) if точки or not неповний_портрет else None
    дж = _джерело_кольору(d)
    з_портрета = дж == ДЖЕРЕЛО_ТИПОВЕ
    о = (None if з_портрета else cs.hx(d["очі"]) if d.get("очі") or not неповний_портрет else None)
    вл = [cs.hx(x) for x in волосся(d, без_підстановки=неповний_портрет)]
    if вл:
        вл = зсув_волосся(вл, d.get("L_волосся"))
    if ш is not None and d.get("L_шкіра") is not None:
        ш = (float(d["L_шкіра"]), ш[1], ш[2])
    F = cs.features(ш, вл[0] if вл else None, о, джерело=дж)
    if з_портрета:
        _очі_моделі(F, d)
    for i, lab in enumerate(вл[1:], start=2):
        F = cs.перерахувати_рису(F, "волосся_%d" % i, lab, kind="волосся")
    # НЕВИЗНАЧЕНІСТЬ СВІТЛОТИ ВОЛОССЯ — НА ВСІ ПАСМА. `cs.features`
    # кладе `L_невизначеність` лише тим рисам, які будує сама; пасма 2..N додає
    # `перерахувати_рису`, яка не знає протоколу зйомки. Без копіювання набори полів
    # пасом розійшлися б і `колір_простір_риси.поля_риси` не зміг би побудувати
    # палітру для неоднобарвного волосся. Величина одна на всі пасма за побудовою:
    # вони зняті з ОДНОГО кадру за одним протоколом.
    _невизн = (F.get("волосся") or {}).get("L_невизначеність")
    if _невизн is not None:
        for _рс in F:
            if _рс.startswith("волосся"):
                F[_рс]["L_невизначеність"] = _невизн
    # Кільце — окрема риса з тим самим джерелом, що й решта портрета.
    if d.get("очі_кільце"):
        F = cs.перерахувати_рису(F, "очі_кільце", cs.hx(d["очі_кільце"]), kind="очі")
    F["_meta"]["protocol"] = дж
    return F, ш, вл, о, точки

БІЛИЙ_У_САМОЗВІТ = {"вершковий": "теплий", "оптичний": "холодний"}

def нормувати_елісітацію(вх):
    """Одна відповідь людини → два словники, які чекають РІЗНІ споживачі.

    `palette.тепло_з_елісітації` чекає білий як «вершковий/оптичний», а
    `palettes._hue` — той самий білий як «теплий/холодний». Обидва мовчать на
    чужому слові: перший не додає каналу, другий тихо рахує нуль. Контракт при
    цьому формально не порушено. Тому переклад живе в ОДНОМУ місці — тут, на межі.
    """
    в = dict(вх or {})
    драп = {k: в[k] for k in ("білий", "метал", "нейтралі") if в.get(k)}
    # СЛОВНИК ДРАПІРОВКИ → СЛОВНИК РАНГУ. `bases.температура_людини` чекає
    # метал ∈ {золото, срібло}, нейтраль ∈ {теплі, холодні}, білий ∈ {теплий,
    # холодний}; показ віддає метал «теплі/холодні», білий «золото/срібло», а
    # `нейтралі` в показі — про хрому (приглушені/яскраві), не про температуру.
    # Без перекладу всі три голоси стають None, і палітра рахується лише з фото.
    _МЕТАЛ = {"теплі": "золото", "теплий": "золото", "золото": "золото",
              "холодні": "срібло", "холодний": "срібло", "срібло": "срібло"}
    _БІЛИЙ = {"золото": "теплий", "теплий": "теплий", "вершковий": "теплий",
              "срібло": "холодний", "холодний": "холодний", "оптичний": "холодний"}
    if в.get("метал") in _МЕТАЛ:  в = dict(в, метал=_МЕТАЛ[в["метал"]])
    if в.get("білий") in _БІЛИЙ:  в = dict(в, білий=_БІЛИЙ[в["білий"]])
    сам = {}
    if в.get("метал"):  сам["метал"] = в["метал"]
    if в.get("білий"):  сам["білий"] = БІЛИЙ_У_САМОЗВІТ.get(в["білий"], в["білий"])
    if в.get("барви"):  сам["барви"] = в["барви"]
    # хрома: «нейтралі приглушені/яскраві» — це і є самозвіт про власні барви для
    # bases.ЦІЛЬ_ХРОМИ (6 / 22); без нього ціль стояла на 12 і всі кольорові основи
    # вилітали в «не радимо»
    if в.get("нейтралі") in ("приглушені", "яскраві") and not сам.get("барви_хрома"):
        сам["барви_хрома"] = в["нейтралі"]
    return dict(драп=драп, самозвіт=сам)


def збірка(d, донорський=False, лише_палітра=False, *, неповний_портрет=False):
    """dict із JS → (F, T, зріст, опис сценарію `сценарій.Сценарій`).

    Лише кольоровий екран і його вибір не потребують зросту: без нього тіло
    не рахується, а аудит конвеєра зберігає невідомий масштаб і брак виміру.
    Решта викликів, включно з донорським, вимагають справжній вимір.
    """
    import fit as ПС
    from паспорт_нагоди import сценарій_з
    F0, ш, вл, о, _ = features(d, неповний_портрет=неповний_портрет)
    # ── БЕЗ ЗРОСТУ — НАЗВАНА ПОМИЛКА, НЕ ЗАМОВЧУВАННЯ ────────────────────────
    # Межа моста мусить сказати, чого бракує, тим самим способом, що й решта воріт:
    # названим полем, а не `TypeError: float() argument`.
    _нема_зросту = d.get("зріст") in (None, "")
    if _нема_зросту and (not лише_палітра or донорський):
        raise ValueError("зріст: виміру нема — поле обов'язкове (profile.масштаб і "
                         "посадка.тіло стоять на ньому); вгадувати його нічим")
    зріст = None if _нема_зросту else float(d["зріст"])
    об = {k: float(v) for k, v in d["обхвати"].items() if v not in (None, "")}
    if донорський:
        import brief as Б
        ш, в, о, об = Б.донор(ш, вл[0], о, об)
        зріст = зріст - 12.0 if зріст >= 165 else зріст + 12.0
        # РОЗКИД НЕ ЗБЕРІГАЄТЬСЯ: інакше правило «волосся саме несе крок світлоти»
        # було б однаковим у B і C, тобто плацебо на ньому було б сліпе. Розкид —
        # така сама властивість людини, як і контраст, тож донор його теж вивертає:
        # у донора волосся однотонне.
        #
        # Донор змінює кольори, але не спосіб, у який їх отримано (вимір кадру — «uncontrolled», не `source` входу).
        F = cs.features(ш, в, о, джерело=(F0.get("_meta") or {}).get("protocol") or _джерело_кольору(d))
        _ОЗ.перенести_очі(F0, F)
    else:
        F = F0
    # АКСЕСУАРНІ ВИМІРИ ЇДУТЬ ТИМ САМИМ ПАКЕТОМ (Н-V13-025), щоб таблиця воріт
    # розміру в `accessory` була доступна всім чотирьом рукам. Нічого не чистимо й
    # не приводимо: `fit.тіло` сам відсіює `None`, зводить до float і кидає
    # ValueError на невідомому імені — один сторож, а не два розбіжні.
    T = (ПС.тіло(зріст, об, аксесуарні=d.get("аксесуарні"))
         if зріст is not None and len(об) >= 3 else None)
    с = d.get("сценарій") or {}
    # ОПИС СЦЕНАРІЮ БУДУЄТЬСЯ ТУТ, РАЗ НА МЕЖІ (наряд Код-сценарій-один-опис): поля нагоди з паспорта стають описом
    # `сценарій.Сценарій` — значення, джерело (її слово · тлумачення · форма · типове · виведене) і «невідомо», — і
    # далі його несуть цілим: пакет (`міст_основи.пакет` → `pipeline.підготувати`) і суд (`міст_відповіді`).
    kw = сценарій_з({k: v for k, v in с.items() if v not in (None, "")}, d.get("паспорт"))
    # ── МАКІЯЖ ЯК РИСИ ПРОФІЛЮ ────────────────────────────────────────────────
    # Кольори макіяжу дають ВЛАСНІ дуги тону — по одній на зону, без усереднення
    # (`colorspace.додати_макіяж`), бо сам прапорець «є / нема» не несе кольору.
    #
    # ДОНОР ВИВЕРТАЄ МАКІЯЖ ТЕЖ. Це не педантизм: рука C — плацебо, і будь-яка
    # властивість людини, яку донор ЗБЕРІГАЄ, робить сліпий тест сліпим саме на
    # цій осі. Макіяж вивертається за
    # тим самим правилом, що й волосся в `brief.донор`: світлота макіяжу йде на
    # протилежний від шкіри кінець шкали, тон лишається (тон і є те, що правило
    # читає, — його підміна зробила б донора нерозпізнаваним як людину).
    мк = с.get("макіяж")
    if донорський and isinstance(мк, dict):
        _ц = 8.0 if ш[0] >= 50 else 92.0
        мк = {з: Б.перефарбувати_L(h, _ц) if isinstance(h, str) and h.startswith("#") else h
              for з, h in мк.items()}
    F, _дод = cs.додати_макіяж(F, мк)
    return F, T, зріст, kw


def якір(d):
    """Кут тону, який обрала людина, як float; None — якоря не подано."""
    я = d.get("якір")
    return None if я in (None, "") else float(я)


def індекс_гілки(розвилка, гілка, схема):
    """Індекс обраної гілки в розвилці ЦЬОГО пакета.

    Ім'я сильніше за номер: номер — це позиція в переліку, який під різними
    намірами різний, а ім'я те саме скрізь. Коли імені нема (CLI, стенд,
    сценарій без імені), використовується запасний шлях — номер із
    затиском по довжині. Коли ім'я є, але в розвилці його нема (схема зникла з
    корпусу), теж номер: мовчки підставляти нуль було б вибором за людину."""
    if схема:
        for i, г in enumerate(розвилка):
            if г["схема"] == схема:
                return i
    return None if гілка is None else min(гілка, len(розвилка) - 1)



ІНШІ_БАРВИ = {"яскраві": "приглушені", "приглушені": "яскраві"}


def самозвіт(d, донорський=False):
    """Те, що людина сказала про себе, а не те, що видно на фото.

    Вісь colour contrast (K-CLR-01 §2) рахується з барвності волосся й ОЧЕЙ, але
    з телефонного фото не стверджується: надійність хроми 0.35 при порозі 0.5.
    Канон (K-PC-01) прямо приписує в цьому місці питати людину, а не вимірювати.
    Донор перекидає відповіді — це властивість особи, отже плацебо її вивертає."""
    с = dict(d.get("самозвіт") or {})
    if донорський:
        if с.get("барви"):
            с["барви"] = ІНШІ_БАРВИ.get(с["барви"], с["барви"])
        if с.get("метал"):
            с["метал"] = {"золото": "срібло", "срібло": "золото"}.get(с["метал"], с["метал"])
    return с


def нормалізувати_вхід(d):
    """Сирі відповіді драпіровки → два ключі входу, ОДИН раз на межі моста.

    Переклад мусить стояти на межі моста, а не лише в `запити`: показ шле
    `драп_сирий` усім ендпойнтам, тоді як `палітри` читає `самозвіт`, а
    `від_моделі` не читає жодного з двох. Інакше екран палітри й суддя сліпі до
    єдиного каналу, що не залежить від камери.

    Окрема функція потрібна тому, що `виклик` — диспетчер для JS, а частина
    ендпойнтів приходить у код повз нього (тести, прилади, `стенд_знімок`).
    Межа, яку можна обійти, — не межа.

    Явно поданий `самозвіт` сильніший за сирі картки: це те саме правило, що вже
    стояло в `запити`, і воно потрібне рукам експерименту, які подають самозвіт
    вивернутим (`_самозвіт(d, донорський=True)`).
    """
    if d.get("драп_сирий") and not d.get("самозвіт"):
        _е = нормувати_елісітацію(d["драп_сирий"])
        return dict(d, самозвіт=_е["самозвіт"], драп=_е["драп"])
    return d


def перефарбувати(hex_, L=None):
    """Той самий hex зі світлотою `L` (a*, b* незмінні); без `L` — нормалізований hex."""
    lab = cs.hx(hex_)
    if L is not None:
        lab = (float(L), lab[1], lab[2])
    r, g, b = cs.to_rgb(*lab)
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v * 255))) for v in (r, g, b))


def hex_lch(L, C, h):
    """hex із LCh; хрома обрізається стелею `cs.c_max`, щоб колір був відтворюваний. Перетворення — модуля
    (`lab_з_lch`, `hex_з_lab`: канал обрізано до [0, 1] до округлення — те саме число, що обрізати після)."""
    return _КПП.hex_з_lab(_КПП.lab_з_lch(L, min(C, cs.c_max(L, h)), h))


def чипи(_вхід=None):
    """Запасний шлях без фото: сходинки, з яких людина обирає себе. Хеси
    рахуються тут, а не вписані рукою, щоб сидіти в тому самому просторі, у
    якому код потім міряє.

    `_вхід` НЕ ЧИТАЄТЬСЯ СВІДОМО: сигнатура одна на всі ендпойнти диспетчера
    `bridge.виклик` (`функція(вхід)`), а сходинки не залежать від жінки — вона
    саме з них себе й обирає, коли фото ще нема."""
    ш = [перефарбувати(hex_lch(L, 26, 52)) for L in (34, 44, 54, 63, 71, 78, 84)]
    в = [перефарбувати(hex_lch(L, c, h)) for L, c, h in
         ((12, 4, 60), (24, 14, 55), (36, 20, 58), (48, 24, 62), (60, 26, 70),
          (72, 26, 78), (82, 18, 82), (40, 40, 32))]
    о = ["#3b2c22", "#5d4632", "#7d6a4f", "#6f7f6a", "#5b7f86", "#7c98b5", "#9aa7ad", "#4a5b46"]
    return _json.dumps(dict(шкіра=ш, волосся=в, очі=о), ensure_ascii=False)


