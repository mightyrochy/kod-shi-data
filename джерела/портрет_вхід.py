ПОРТРЕТ_ПРИДАТНИЙ = "usable"


# ═══════════ ЇЇ КОЛЬОРИ З ПОРТРЕТА: ВІДПОВІДЬ МОДЕЛІ (Е2-межі-показу, ПС-13) ═══════════
# Показ сам вирізав JSON (колишній `розібратиКолір`: від першої `{` до останньої `}`) — власний читач поза реєстром:
# обгортка, два об'єкти чи обірвана відповідь ламали його, а перевірки схемою, повтору й нотаток не було.
# Тепер відповідь читає реєстр (`схеми_розбору`, форма PORTRAIT_COLOURS): `протокол.розбір_за_схемою` (ремонт форми,
# обгортка, кілька об'єктів), схема `ПОРТРЕТ_V1`, ОДИН повтор словами (`повтор` — те, що показ вкладає в промпт).
# Запасного читача «рядки з hex» (коли JSON не став) нема: прозу з мітками код не читає — це розбіжність форми, і
# повтор каже її словами (Е2-межі п.4).
# Показ лише несе текст туди й результат назад; Pyodide піднімається поки модель дивиться на фото.
# ПРИЧИНА, А НЕ ПОМИЛКА ФОРМИ: відмова — перше слово поля `photo` (модель інколи переписує підпис скелета);
# `photo: true` чи нема — розбіжність (повтор), а не «придатне»; hex без ґратки читається. Решту слідів називають `нотатки`, не мовчки.
_HEX_КОЛЬОРУ = _re.compile(r"#?([0-9a-fA-F]{6})")
_ВИД_СВІТЛА = ("none", "yellow", "blue")
_СИЛА_КОРЕКЦІЇ = ("none", "slight", "strong")


def _hex_кольору(значення):
    """Рядок чи список → hex-и `#rrggbb` малими літерами, у порядку відповіді; не-hex пропущено."""
    частини = значення if isinstance(значення, (list, tuple)) else [значення]
    вих = []
    for ч in частини:
        for слово in _re.split(r"[\s,;]+", str(ч if ч is not None else "").strip()):
            м = _HEX_КОЛЬОРУ.fullmatch(слово)
            if м:
                вих.append("#" + м.group(1).lower())
    return вих


def прийняти_колір(відповідь):
    """Сира відповідь моделі про кольори з портрета → dict(стан, шкіра, волосся, очі, колір_очей, кільце, освітлення, відмова,
    джерело, нотатки, помилки, повтор, зони).

    `стан`: «готово» (шкіра, волосся й око прочитано), «відмова» (`відмова` — код причини; кольорів із відмови не
    беремо: hex ішов би в розрахунок, який не вміє сумніватись) або «брак_точок» (чого не прочитано — `помилки`).
    `джерело` — «json». `повтор` — рядок JSON для ОДНОГО повторного виклику (`помилка_формату`),
    лише коли нічого не прочиталось і JSON не став або обірвався; готовий і відмова повтору не мають."""
    import портрет_вимір as _ПВ
    import протокол as _ПР
    текст = str(відповідь or "")
    об, причина, нот = _ПР.розбір_за_схемою(текст, "PORTRAIT_COLOURS")
    нотатки = list(нот.get("нормалізовано") or [])
    р = dict(стан="брак_точок", шкіра=[], волосся=[], очі=None, колір_очей=None, кільце=None, освітлення=None,
             відмова=None,
             джерело="json", нотатки=нотатки, помилки=[], повтор=None, зони={})
    if isinstance(об, dict) and any(к in об for к in ("photo", "skin", "hair", "eyes")):
        # «photo» без коду (нема чи `true`) — розбіжність зі схемою, як будь-яка інша: повтор називає її словами
        # (Е2-межі п.4); доти код сам читав його як «usable» — і hex ішов у розрахунок без її придатності
        фото = об.get("photo")
        if isinstance(фото, str):
            код = (_re.match(r"[a-z_]+", фото.strip().lower()) or [""])[0] or НЕВІДОМО
            if код != ПОРТРЕТ_ПРИДАТНИЙ:
                return dict(р, стан="відмова", відмова=код)
        р["шкіра"], р["волосся"] = _hex_кольору(об.get("skin")), _hex_кольору(об.get("hair"))
        р["очі"] = (_hex_кольору(об.get("eyes")) or [None])[0]
        р["кільце"] = (_hex_кольору(об.get("limbal_ring")) or [None])[0]
        # сім'я очей — код моделі із закритого переліку (`face_features.КОДИ_ОЧЕЙ`); поза ним — «невідомо» (None)
        код_очей = str(об.get("eye_colour") or "").strip().lower()
        р["колір_очей"] = код_очей if код_очей in _ОЗ.КОДИ_ОЧЕЙ else None
        вид = об.get("light_cast") if об.get("light_cast") in _ВИД_СВІТЛА else None
        сила = об.get("light_correction") if об.get("light_correction") in _СИЛА_КОРЕКЦІЇ else None
        if вид or сила:
            р["освітлення"] = dict(cast=вид, correction=сила)
        # рамки зон для виміру кадру кодом (`портрет_вимір`): показ ріже їх із портрета й шле в `колір` {виміряти}
        р["зони"] = _ПВ.рамки(об.get("zones"))
        р["помилки"] = _ПР.перевірити(_ПР.ПОЗА_ПАКЕТОМ["PORTRAIT_COLOURS"],
                                      dict(об, photo=ПОРТРЕТ_ПРИДАТНИЙ) if isinstance(фото, str) else об)
    else:
        # не JSON — розбіжність: один повтор словами, а не hex із рядків прози (запасного читача «рядки» нема)
        р["помилки"] = [_ПР._пом("", причина or _ПР.ПРИЧИНА_НЕМАЄ_JSON)]
    брак = [п for п, в in (("skin", р["шкіра"]), ("hair", р["волосся"]), ("eyes", р["очі"])) if not в]
    вада_фото = [п for п in р["помилки"] if п.get("де") == "photo"]
    if not брак and not вада_фото:
        return dict(р, стан="готово")
    р["помилки"] = [п for п in р["помилки"] if п.get("що") != "required_missing" or п.get("де") == "photo"] \
        + [_ПР._пом(п, "no_hex_colour") for п in брак]
    # промпт читання портрета — англійський (п.12), тож і повтор англійським дротом (`помилка_en`)
    р["повтор"] = _json.dumps(_ПР.помилка_en(_ПР.обʼєкт_помилки(р["помилки"][:8], "PORTRAIT_COLOURS")),
                              ensure_ascii=False)
    return р
