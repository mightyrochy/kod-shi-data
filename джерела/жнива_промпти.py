# (1) бере вікно з налаштування рушія — `loaded_context_length` у `_стан_моделі`, на слот, коли слоти відомі (`lms ps`);
# (2) міряє токени тексту (`пакет_моделі.токенів`) і кадрів (клітинки 28×28 зору Qwen-VL з розмірів JPEG) × поправка з
# `prompt_tokens` попереднього запиту цієї моделі, разом зі стелею відповіді; (3) не влазить — знімає кадри з кінця (перший —
# сама річ, решта — додатковий ракурс), а один кадр і текст не влазять — виняток `prompt_exceeds_model_window` з числами
# ДО запиту. Вікна не знаємо (LM Studio мовчить, моделі в пам'яті нема) — не міряємо. Слотів без CLI не видно (`_поділ`):
# тоді вікно — весь контекст, а поділ на потоки стереже `звірити_модель` на старті прогону.
ТОКЕНІВ_КАДРА_НЕВІДОМОГО = 1400         # кадр, чий розмір не прочитано з JPEG: 1024×1024 у клітинках 28×28
КЛІТИНКА_КАДРА = 28
_ВІКНА_ЖНИВ, _ПОПРАВКИ_ЖНИВ = {}, {}


def _токенів_кадра(b64):
    """Токени одного кадра: клітинок 28×28 на його розмір, прочитаний із заголовка JPEG (SOF); не прочитано — 1 400."""
    байти = base64.b64decode(b64)
    і = 2
    while і + 9 < len(байти) and байти[і] == 0xFF:
        if байти[і + 1] in (0xC0, 0xC1, 0xC2, 0xC3, 0xC5, 0xC6, 0xC7, 0xC9, 0xCA, 0xCB, 0xCD, 0xCE, 0xCF):
            висота, ширина = struct.unpack(">HH", байти[і + 5:і + 9])
            return math.ceil(ширина / КЛІТИНКА_КАДРА) * math.ceil(висота / КЛІТИНКА_КАДРА)
        і += 2 + struct.unpack(">H", байти[і + 2:і + 4])[0]
    return ТОКЕНІВ_КАДРА_НЕВІДОМОГО


def _вікно_запиту(модель):
    """Вікно (токени) одного запиту до `модель` з налаштування LM Studio (`_стан_моделі`): контекст на слот, коли слоти
    відомі, інакше весь контекст; 0 — вікна не знаємо. Скидається `звірити_модель` при перезавантаженні."""
    if модель not in _ВІКНА_ЖНИВ:
        try:
            контекст, слотів = _стан_моделі(модель)
        except Exception:                             # noqa: BLE001 — LM Studio мовчить = вікна не знаємо
            return 0
        if контекст:
            _ВІКНА_ЖНИВ[модель] = контекст // max(слотів, 1)
    return _ВІКНА_ЖНИВ.get(модель, 0)


def _вмістити_у_вікно(модель, текст, кадри, стеля, вікно):
    """(кадри, сира оцінка входу): текст і кадри разом зі стелею відповіді влазять у `вікно` — або це кадри без
    знятих з кінця, або виняток `prompt_exceeds_model_window`. `вікно` 0 — не міряємо."""
    if not вікно:
        return кадри, 0
    поправка = _ПОПРАВКИ_ЖНИВ.get(модель, 1.0)
    кадри = list(кадри)
    токенів_кадрів = [_токенів_кадра(к) for к in кадри]
    сира = оцінка_токенів(текст) + sum(токенів_кадрів)
    вхід_токенів = math.ceil(сира * поправка)
    до = вхід_токенів
    while len(кадри) > 1 and вхід_токенів + стеля > вікно:
        кадри.pop()
        токенів_кадрів.pop()
        сира = оцінка_токенів(текст) + sum(токенів_кадрів)
        вхід_токенів = math.ceil(сира * поправка)
    if вхід_токенів + стеля > вікно:
        raise ValueError("prompt_exceeds_model_window · tokens≈%d + max_tokens=%d > window=%d · кадри й текст не вмістити"
                         % (вхід_токенів, стеля, вікно))
    if вхід_токенів != до:
        print("промпт жнив скорочено до вікна: кадрів %d · tokens≈%d→%d + max_tokens=%d ≤ window=%d"
              % (len(кадри), до, вхід_токенів, стеля, вікно), file=sys.stderr)
    return кадри, сира


def _запит(модель, текст, картинки, тайм=240, повтори=2, токенів=600, з_ужитком=False):
    """Один запит до LM Studio з одним або кількома зображеннями → розібраний JSON (з `з_ужитком` — пара
    (JSON, usage)). Відповідь читає реєстр (форма «ЖНИВА_ОПИС», наряд Е2-межі-поза-реєстром): доти тут, у
    `жнива_збагачення.спитати` і `проба_мотиву_фото.v2` стояли три копії зрізу «від першої { до останньої }» + `json.loads`,
    а повтор на не-JSON слав той самий текст. Тепер наступна спроба несе розбіжність словами
    (`промпт_повтору`); обрив і помилка сервера — та сама спроба, як доти."""
    форма = _СВ.СХЕМИ_ВІДПОВІДІ["ЖНИВА_ОПИС"]
    вікно = _вікно_запиту(модель)
    # ЯКЩО ТУТ ПОЧНЕ ЛІТАТИ «не JSON: ''» — перше, що перевіряти, це чи не ДУМАЄ модель
    # перевіряти, це чи не ДУМАЄ модель. У моделі з `capabilities.reasoning.default: on`
    # так, qwen3-vl-8b і gemma-4-12b — ні) відповідь іде в `reasoning_content`, а `content`
    # лишається порожній, поки не вичерпано `max_tokens`: на 600 токенах думка не встигає
    # договоритись, і жнива бачать не помилку моделі, а порожній рядок. Вимикається рівно
    # одним способом із семи випробуваних — `"reasoning_effort": "none"` у цьому тілі;
    # `/no_think` у тексті робить ВДВІЧІ гірше. Тут його нема, бо типова модель не думає.
    # І ЯКЩО КОЛИСЬ БУДЕ: перемикач слухається не моделі, а ЗАВАНТАЖЕННЯ. Той самий файл,
    # піднятий `lms load qwen/qwen3.5-9b` (ключем каталогу), глушиться; піднятий
    # `lms load qwen3.5-9b@q4_k_m` (голим іменем варіанта) — ні, і поле мовчки не діє.
    # Тобто «поле шлемо» ще не значить «модель не думає»: перевіряти відповіддю.
    запит_текст = текст
    for спроба in range(повтори + 1):
        картинки, сира = _вмістити_у_вікно(модель, запит_текст, картинки, токенів, вікно)
        картинки_зміст = [{"type": "image_url", "image_url": {"url": "data:image/jpeg;base64," + b64}}
                          for b64 in картинки]
        дані = json.dumps({"model": модель, "temperature": 0, "max_tokens": токенів,
                           "messages": [{"role": "user", "content": [{"type": "text", "text": запит_текст}]
                                         + картинки_зміст}]}).encode("utf-8")
        try:
            зап = urllib.request.Request(СЕРВЕР, data=дані, headers={"Content-Type": "application/json"})
            with urllib.request.urlopen(зап, timeout=тайм) as в:
                відп = json.load(в)
            if сира and (відп.get("usage") or {}).get("prompt_tokens"):
                _ПОПРАВКИ_ЖНИВ[модель] = відп["usage"]["prompt_tokens"] / сира
            текст_від = (відп["choices"][0]["message"]["content"] or "").strip()
            об, причина, _ = форма.прочитати(текст_від)
            if об is None:
                запит_текст = форма.промпт_повтору(текст, причина)
                raise ValueError("не JSON (%s): %r" % (причина, текст_від[:100]))
            return (об, відп.get("usage", {})) if з_ужитком else об
        except Exception as _e:
            import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
            if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
            if спроба == повтори:
                raise
            time.sleep(3)


# ── КОНТЕКСТ ЗАВАНТАЖЕНОЇ МОДЕЛІ: ПАСТКА JIT ─────────────────────────────────
# Just-in-time завантаження в LM Studio ввімкнене типово, і воно бере модель з
# контекстом 4096 на ЧОТИРИ слоти — 1024 токени на потік. Один запит жнив із
# фото виміряно тут-таки, через `usage` самої відповіді: prompt 1939–1961 токен
# на трьох речах поспіль плюс до 600 на відповідь, тобто ~2 560 на потік.
# Виміряно 24.09 дев'ятьма справжніми запитами трьома потоками:
#   JIT (контекст 4096 на 4 слоти)  → 0 ок, 9 HTTP 400
#   `-c 16384 --parallel 3`         → 9 ок, 0 збоїв
# Поодинокий запит JIT переживає (6 з 6), і саме тому пастка не видна в
# одиничних пробах — вона з'являється рівно тоді, коли прогін іде потоками.
# ЧОМУ ЦЕ ТУТ, А НЕ В СКРИПТІ ЗАПУСКУ (слово власника 24.09: «Я сам буду
# запускати»). Власник піднімає LM Studio рукою, і тоді модель приходить із
# JIT-контекстом. Прогін готує свою залежність сам, у мить запуску, а не
# сподівається на гачок при вході в Windows.
КОНТЕКСТ_НА_ПОТІК = 4096               # виміряні 2 560 плюс запас на довший промпт набору
КОНТЕКСТ_ВИМІРЯНИЙ = 16384             # саме та збірка, на якій вийшло 9 з 9
LMS = os.path.join(os.path.expanduser("~"), ".lmstudio", "bin", "lms.exe")


def _стан_моделі(модель):
    """(контекст, слотів) моделі в пам'яті LM Studio; (0, 0) — у пам'яті її нема.

    Слотів (`--parallel`) знає лише `lms ps --json`; HTTP `/api/v0/models` дає
    `loaded_context_length` і про поділ мовчить. Коли CLI нема (Linux, чужа
    машина), слотів повертаємо 0 — «невідомо», і поріг рахується за числом
    потоків прогону, тобто по найгіршому.
    """
    if os.path.exists(LMS):
        сире = subprocess.check_output([LMS, "ps", "--json"], timeout=60).decode("utf-8", "replace").strip()
        for м in json.loads(сире or "[]"):
            if модель in (м.get("identifier"), м.get("modelKey")):
                return int(м.get("contextLength") or 0), int(м.get("parallel") or 1)
        return 0, 0
    with urllib.request.urlopen(СЕРВЕР.split("/v1/")[0] + "/api/v0/models", timeout=15) as в:
        for м in json.load(в).get("data", []):
            if м.get("id") == модель and м.get("state") == "loaded":
                return int(м.get("loaded_context_length") or 0), 0
    return 0, 0


def _поділ(слотів, потоків):
    """Словами: на скільки слотів поділено контекст — чи що поділу ми не бачимо.

    Без `lms.exe` LM Studio каже саму довжину контексту й мовчить про поділ, і
    поріг рахується по числу потоків — припущенням, не виміром. Рядок для людини
    мусить це розрізняти, інакше він стверджує виміряне там, де його нема
    (видно руками 24.09: «контекст 16384 на 3 слот(ів)» на машині, де слотів
    ніхто не питав).
    """
    return "%d слот(ів)" % слотів if слотів else "%d потік(ів) (поділу без CLI не видно)" % потоків


def звірити_модель(модель, потоків, лагодити=True):
    """Чи витримає модель у пам'яті стільки потоків → (гаразд, рядок для людини).

    Мовчазного падіння на 400-х не буває: або контекст підходить, або модель
    перевантажено з потрібним, або прогін спиняється рядком, який називає число
    і команду. `лагодити=False` — лише подивитись, нічого не чіпаючи.
    """
    try:
        контекст, слотів = _стан_моделі(модель)
    except Exception as _e:
        return False, "LM Studio не відповідає (%s) — підніми його і повтори" % type(_e).__name__
    слот = контекст // max(слотів or потоків, 1)
    if слот >= КОНТЕКСТ_НА_ПОТІК:
        return True, "модель «%s»: контекст %d на %s — %d на потік, вистачає" % (
            модель, контекст, _поділ(слотів, потоків), слот)
    чому = ("модель «%s» не завантажена — JIT візьме її з контекстом 4096 на 4 слоти" % модель
            if not контекст else
            "модель «%s» завантажена з контекстом %d на %s — %d на потік" % (
                модель, контекст, _поділ(слотів, потоків), слот))
    треба = max(КОНТЕКСТ_НА_ПОТІК * потоків, КОНТЕКСТ_ВИМІРЯНИЙ)
    рука = "lms load %s --gpu max -c %d --parallel %d -y" % (модель, треба, потоків)
    if not (лагодити and os.path.exists(LMS)):
        return False, "%s, а треба %d на потік: %d потоків упадуть на HTTP 400.\n  Запусти `%s` — або `підняти_сервери.ps1` поруч із жнивами" % (
            чому, КОНТЕКСТ_НА_ПОТІК, потоків, рука)
    print("%s — перезавантажую: %s" % (чому, рука), flush=True)
    _ВІКНА_ЖНИВ.clear()
    subprocess.call([LMS, "unload", "--all"], timeout=120)
    subprocess.call([LMS, "load", модель, "--gpu", "max", "-c", str(треба),
                     "--parallel", str(потоків), "--identifier", модель, "-y"], timeout=900)
    try:
        контекст, слотів = _стан_моделі(модель)
    except Exception as _e:
        return False, "після перезавантаження LM Studio не відповідає (%s)" % type(_e).__name__
    слот = контекст // max(слотів or потоків, 1)
    if слот >= КОНТЕКСТ_НА_ПОТІК:
        return True, "модель «%s» перезавантажена: контекст %d на %s — %d на потік" % (
            модель, контекст, _поділ(слотів, потоків), слот)
    return False, "перезавантаження не помогло: контекст %d на %s. Зроби рукою: %s" % (
        контекст, _поділ(слотів, потоків), рука)


