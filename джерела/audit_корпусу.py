# -*- coding: utf-8 -*-
"""ПОРОДЖУВАЧ ТАБЛИЦЬ «ПРАВИЛА, ЯКИХ КОРПУС НЕ ЗНАЄ».

ЩО ПИШЕ І КУДИ.
  `outfit.ПОЗА_КОРПУСОМ`          — ID, які код цитує, а жодна тема не називає.
  `rule_genus.ЗГАДАНО_БЕЗ_ОЗНАЧЕННЯ` — ID, які тема називає, а форми означення
                                    там не розпізнано (ПИТАННЯ, не вирок).

ЧОМУ ОКРЕМИЙ ФАЙЛ, А НЕ `__main__` У `корпус.py`. Критерій живе в
`корпус.ід_поза_корпусом` — там йому й місце. Але щоб ПОРОДИТИ таблицю, треба
ще й розпізнавач означення, а він один на проєкт і живе в `правила.формулювання`.
`корпус` іде В ПРОДУКТ (замикання від `bridge` тягне його через
`status → audit_contracts`), і `build_артефакт._закриття` бере імпорти AST-обходом
УСЬОГО файла — навіть із `__main__`. Тобто рядок `import правила` в `корпус.py`
клав би прилад у вантаж користувачки: виміряно, замикання росло з 37 модулів до
39. Це рівно те відхилення, яке §1.1 СТАНДАРТУ_КОДУ називає першим («ядро не
імпортує нічого з приладів»), і додавати до нього ще одне ребро заради
бухгалтерії — не варте.

Префікс `audit_` не косметичний: за ним цей файл уже виключають ВСІ три сканери
(`gate_reach._прилад`, `відбиток._НЕ_СИСТЕМА`, `audit_contracts._живі_модулі`),
тож нового рядка в жоден список приладів дописувати не треба.

Прогін:  python3 audit_корпусу.py [--записати]
"""
import os
import sys

_ТУТ = os.path.dirname(os.path.abspath(__file__)) or "."
sys.path.insert(0, _ТУТ)

import корпус as КР

бази_в_тексті = КР.бази_в_тексті
ід_поза_корпусом = КР.ід_поза_корпусом
ід_без_означення = КР.ід_без_означення


# ЧОМУ ПОРОДЖУВАЧ, А НЕ ІМПОРТ КОРПУСУ В `outfit`. Спокуса — щоб `outfit` сам питав
# корпус при імпорті. Не можна: `outfit` іде В ПРОДУКТ (`build_артефакт`
# запаковує замикання від `bridge`), а файлів тем у браузері нема. Модуль ядра,
# який при імпорті читає теку з темами, — це збірка, що падає на користувачі.
# Тому таблиця лишається літералом У КОДІ, але ПИШЕ її не рука, а цей скрипт:
# членство міряється, примітки переносяться.
_ПОЧАТОК = "# ── ПОРОДЖЕНО `python3 audit_корпусу.py --записати` ──"
_КІНЕЦЬ = "# ── КІНЕЦЬ ПОРОДЖЕНОГО ──"


def _цитовані_кодом(тека_коду):
    """ID, які цитує ЖИВИЙ код. Критерій «прилад» — один на проєкт, і він у
    `gate_reach._прилад`: прилад цитує ID за побудовою (він про них і говорить),
    і кожна така згадка вимагала б запису в корпусі — тобто РОЗПОВІДЬ про дірку
    створювала б дірку."""
    import glob as _g
    import gate_reach as _ГД
    з = set()
    for ф in sorted(_g.glob(os.path.join(тека_коду, "*.py"))):
        імя = os.path.basename(ф)
        if _ГД._прилад(імя) or імя in ("корпус.py", "ід_правил.py"):
            continue
        with open(ф, encoding="utf-8", errors="replace") as fh:
            з |= бази_в_тексті(fh.read())
    return з


def _літерал(імя, словник):
    """Словник як рядок-літерал Python — рівно в тій формі, у якій він лежить
    у `outfit.py`, щоб діф показував зміну ЧЛЕНСТВА, а не переформатування."""
    р = ["%s = {" % імя]
    for k in sorted(словник):
        р.append(' "%s": "%s",' % (k, словник[k].replace('"', "'")))
    р.append("}")
    return "\n".join(р)


def _породити(тека_коду):
    """(блок для outfit, блок для rule_genus, поза, без_означення).

    ЧОМУ ДВА БЛОКИ В РІЗНИХ ФАЙЛАХ, А НЕ ОДИН. Ключі `ПОЗА_КОРПУСОМ` — це ID,
    яких у корпусі НЕМА, тож їхня згадка в модулі ядра нічого не піднімає:
    покриття рахується від корпусу. Ключі `ЗГАДАНО_БЕЗ_ОЗНАЧЕННЯ` — навпаки, це
    ПРАВИЛА КОРПУСУ, і таблиця з ними в `outfit.py` зараховувала б їх за «у
    виконуваному коді»: виміряно на першій спробі — два кольорові правила одразу
    повернулись із «коментаря» в «код», тобто бухгалтерія про дірку закривала
    дірку. Тому другий блок живе в `rule_genus` — описовому модулі, який усі три
    прилади (`gate_reach._прилад`, `відбиток._НЕ_СИСТЕМА`,
    `audit_contracts._мета_py`) виключають зі сканування саме тому, що він
    ГОВОРИТЬ про правила, а не виконує їх.
    """
    import правила as _П
    цит = _цитовані_кодом(тека_коду)
    поза = ід_поза_корпусом(цит)
    без = ід_без_означення(цит, set(_П.формулювання()))
    try:
        import outfit as _O
        старі = dict(getattr(_O, "ПОЗА_КОРПУСОМ", {}))
    except Exception:
        старі = {}
    # ПРИМІТКИ ПЕРЕЖИВАЮТЬ ПЕРЕГЕНЕРАЦІЮ. Дрейфувало ЧЛЕНСТВО, а не знання про
    # те, де зміст правила живе під іншим іменем; викидати друге разом із першим
    # означало б лікувати дрейф забуванням.
    for k in поза:
        if старі.get(k):
            поза[k] = старі[k]
    блок_o = [_ПОЧАТОК,
              "# Членство МІРЯЄТЬСЯ (`корпус.ід_поза_корпусом`): ID, якого не називає",
              "# жодна `тема-*.md`. Примітки перенесені з попереднього покоління —",
              "# дрейфувало членство, а не знання, де зміст живе під іншим іменем.",
              _літерал("ПОЗА_КОРПУСОМ", поза),
              _КІНЕЦЬ]
    блок_r = [_ПОЧАТОК,
              "# ТРЕТІЙ СТАН: тему ID НАЗИВАЄ, а форми ОЗНАЧЕННЯ там не розпізнано.",
              "# ⚠ ЦЕ ПИТАННЯ, А НЕ ВИРОК. Розпізнавач (`правила.формулювання`) НЕ",
              "# калібрований: він шукає форму «ID.» на початку рядка й не бачить",
              "# означень усередині пункту списку — перевірено на правилі «tone on",
              "# tone», яке в темі-2 означене саме пунктом і сюди все одно попало.",
              "# Тому в текст людині цей стан НЕ йде: його читає",
              "# `audit_contracts` розділом «ПИТАННЯ», де судить око, а не шаблон.",
              "# І тому таблиця лежить ТУТ, а не в `outfit`: її ключі — правила",
              "# КОРПУСУ, і в модулі ядра вони зарахувались би за «у виконуваному",
              "# коді» (виміряно: два кольорові правила одразу вернулись із",
              "# «коментаря» в «код»), тобто бухгалтерія про дірку закривала б дірку.",
              _літерал("ЗГАДАНО_БЕЗ_ОЗНАЧЕННЯ",
                       {k: "%s називає цей ID; форму означення не розпізнано "
                           "(некалібрований розпізнавач — питання, не вирок)"
                           % ", ".join(x.split("_")[0] for x in v)
                        for k, v in без.items()}),
              _КІНЕЦЬ]
    return "\n".join(блок_o), "\n".join(блок_r), поза, без


if __name__ == "__main__":
    блок_o, блок_r, поза, без = _породити(_ТУТ)
    print("поза корпусом: %d · згадано без означення: %d" % (len(поза), len(без)))
    for імя_ф, блок in (("outfit.py", блок_o), ("rule_genus.py", блок_r)):
        if "--записати" not in sys.argv:
            print(блок)
            continue
        шлях = os.path.join(_ТУТ, імя_ф)
        стар = open(шлях, encoding="utf-8").read()
        і, к = стар.find(_ПОЧАТОК), стар.find(_КІНЕЦЬ)
        if і < 0 or к < 0:
            print("⛔ у %s нема меж породженого блоку — нічого не писав" % імя_ф)
            raise SystemExit(1)
        open(шлях, "w", encoding="utf-8").write(
            стар[:і] + блок + стар[к + len(_КІНЕЦЬ):])
        print("записано: %s" % шлях)
