"""Ч5 — розбір відповіді моделі (`РЕЗУЛЬТАТ.md`, §3 Ч5): єдиний писач `Образ`. Частину пише Н2.

Заглушка Н1 читає записані відповіді старих схем (складання, вибір, опис) без звірки з пулом і повтору; відповідь
не JSON чи без потрібного поля — `Збій`, а не тиша. Збій моделі, який привіз показ, теж `Збій` (частина «модель»).
"""
import json

from .поняття import Образ, Збій, НЕВІДОМО

НАРЯД = "Н2"


def _дані(відп, вид):
    if "збій" in відп:
        з = відп["збій"]
        return Збій(вид=з.get("вид") or "інше", частина="модель", поле=вид, що=з.get("що", ""),
                    секунди=з.get("секунди"))
    текст = відп.get("текст", "")
    try:
        д = json.loads(текст)
    except ValueError as п:
        return Збій(вид="не_json", частина="розбір", поле=вид, що=str(п), сирий=текст)
    return д if isinstance(д, dict) else Збій(вид="схема", частина="розбір", поле=вид, що="не об'єкт", сирий=текст)


def образи(відп, рука, версія):
    д = _дані(відп, "складання")
    if isinstance(д, Збій):
        return д
    if not isinstance(д.get("outfits"), list) or not д["outfits"]:
        return Збій(вид="схема", частина="розбір", поле="outfits", що="нема образів")
    return tuple(Образ(ід=о["id"], рука=рука, джерело="складання", версія_ситуації=версія,
                       речі=tuple({"н": н, "ід": НЕВІДОМО} for н in о.get("items", ())),
                       полюс=о.get("pole", НЕВІДОМО), підпис_en=о.get("caption", ""), день_en=о.get("day", ""))
                 for о in д["outfits"])


def вибір(відп):
    д = _дані(відп, "вибір")
    if isinstance(д, Збій):
        return д
    if not isinstance(д.get("chosen"), str):
        return Збій(вид="схема", частина="розбір", поле="chosen", що="нема обраного")
    return {"обрано": д["chosen"], "чому_en": д.get("why", ""), "прийнято": tuple(д.get("accept", ()))}


def опис(відп):
    д = _дані(відп, "опис")
    if isinstance(д, Збій):
        return д
    if not isinstance(д.get("text"), str) or not д["text"]:
        return Збій(вид="опис_неповний", частина="розбір", поле="text", що="порожній опис")
    return {"text": д["text"], "how_to_wear": tuple(д.get("how_to_wear", ())),
            "wrong_photos": tuple(д.get("wrong_photos", ()))}
