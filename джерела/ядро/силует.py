"""Факти і знання силуету, якими стилістка обґрунтовує добір та пояснення."""
import json
from math import isfinite
from pathlib import Path

from межа_текстів import ВІДОМЕ
from .мітки import застосовна
from .поняття import НЕВІДОМО, НЕ_ПЕВНИЙ

with Path(__file__).with_name("дані").joinpath("силует.json").open(encoding="utf-8") as _файл:
    _ДАНІ = json.load(_файл)
ЗНАННЯ = tuple(_ДАНІ["знання"])
_ДІЇ = _ДАНІ["дії_за_знахідкою"]

_КЛАСИ = {"крій": "cut", "довжина": "length"}
_ОБХВАТИ = {"плечі": "shoulders", "груди": "bust", "талія": "waist", "стегна": "hips"}
_ПОЛЯ_МЕТИ = {"мета": "goal", "мета_важливо": "priorities", "мета_зони": "zones"}
_ОСОБИСТЕ = {"silhouette_measurements", "silhouette_goal"}


def _додатна_міра(значення):
    """Повертає придатну додатну мірку з профілю."""
    if isinstance(значення, bool) or not isinstance(значення, (int, float, str)):
        return None
    try:
        число = float(значення)
    except (ValueError, OverflowError):
        return None
    return число if isfinite(число) and число > 0 else None


def мірки(профіль):
    """Подає зріст і обхвати, передані в профілі. Шаблонні рівні тіла сюди не потрапляють."""
    вхід = профіль.get("мірки", профіль) or {}
    значення = {}
    if зріст := _додатна_міра(вхід.get("зріст")):
        значення["height_cm"] = зріст
    обхвати = вхід.get("обхвати") or {}
    відомі = {дріт: міра for поле, дріт in _ОБХВАТИ.items() if (міра := _додатна_міра(обхвати.get(поле)))}
    if відомі:
        значення["girths_cm"] = відомі
    return значення


def мета(ситуація):
    """Подає мету щодо силуету, яку вона озвучила в розмові."""
    факти = ситуація.сказала
    return {дріт: {"value": факт.значення, "quote": факт.уривок}
            for поле, дріт in _ПОЛЯ_МЕТИ.items() if (факт := факти[поле]).джерело == "її_слова"}


def ознаки(річ):
    """Повертає той самий крій і край, що йдуть до суду, з походженням кожного класу."""
    джерела = {"крамниця", "фото"} if річ.фото else {"крамниця"}
    return {дріт: {"value": факт.значення, "source": факт.джерело}
            for поле, дріт in _КЛАСИ.items() if застосовна(поле, річ.слот)
            and (факт := річ.поля[поле]).джерело in джерела and факт.значення not in (НЕВІДОМО, НЕ_ПЕВНИЙ)}


def додати_факти(межа, записи, ситуація, профіль):
    """Нумерує окремо річ, її класи, мірки людини й озвучену мету."""
    for адреса, номер in межа.адреси_речей.items():
        for поле, зміст in ознаки(записи[адреса]).items():
            межа.факт(ВІДОМЕ, dict(field=поле, **зміст), (номер,))
    for поле, джерело, значення in (("silhouette_measurements", "profile", мірки(профіль)),
                                    ("silhouette_goal", "її_слова", мета(ситуація))):
        if значення:
            межа.факт(ВІДОМЕ, dict(field=поле, source=джерело, value=значення))


def додати_дію_знахідки(межа, номер, заява):
    """Прив'язує дію під час примірки до номера та ідентифікатора судового факту."""
    текст = _ДІЇ.get(заява["код"])
    if текст and (заява.get("вага") or 0) > 0:
        межа.факти[номер].update(fit_action=текст, finding_id=заява["ід"])


def поради_знахідок(межа):
    """Дає дію з опорою на вихід суду та названі ним речі."""
    рядки = []
    for номер, факт in межа.факти.items():
        if текст := факт.get("fit_action"):
            про = {номер: факт["state"], **{н: межа.факти[н]["state"] for н in факт.get("items", ())}}
            рядки.append(dict(about=про, says=текст, запасний_текст=текст, finding=факт["finding_id"]))
    return рядки


def _групи(межа):
    """Знаходить пронумеровані класи одягу й особисті факти в межі картки."""
    класи = {н: ф["items"] for н, ф in межа.факти.items()
             if ф["state"] == ВІДОМЕ and ф.get("field") in _КЛАСИ.values() and ф.get("items")}
    особисте = {н for н, ф in межа.факти.items() if ф["state"] == ВІДОМЕ and ф.get("field") in _ОСОБИСТЕ}
    return класи, особисте


def правила_картки(межа):
    """Дає стилістці знання класів і спосіб обґрунтувати речення в картці."""
    класи, особисте = _групи(межа)
    if not класи:
        return ()
    опора = ("Пов’яжи ефект з її мірками або її метою та вкажи номер цього факту в about. " if особисте else
             "Опиши, як поєднання речей веде погляд або створює об’єм. ")
    return ("У text додай одне речення про те, що цей склад робить із силуетом. Назви річ, її крій чи край "
            "і додай до about номери речі та її крою або краю. " + опора,
            "Мірки в профілі дозволяють порівнювати тільки записані обхвати. Сам зріст не показує пропорцій ніг або "
            "корпусу. Підкреслити або сховати ділянку можна за її метою. Про край із джерелом «крамниця» кажи зі слів "
            "крамниці, а клас із фото описує край на моделі в кадрі. Без мірок опиши ефект одягу для силуету загалом. "
            "Якщо варто звірити розмір, припуск або положення краю, порадь одну дію для примірки або таблиці мірок.",
            *ЗНАННЯ)


def перевірити_речення(межа, речення):
    """Повертає речення, у яких класи й особисті факти мають опору на названу річ."""
    класи, особисте = _групи(межа)
    if not класи:
        return речення, []
    прийняті, розбіжності = [], []
    описано = False
    for рядок in речення:
        про = рядок["about"].keys()
        ознаки_у_рядку = класи.keys() & про
        особа_у_рядку = особисте & про
        є_речі = all(про & set(класи[н]) for н in ознаки_у_рядку)
        if not є_речі or (особа_у_рядку and not ознаки_у_рядку):
            розбіжності.append(dict(чому="silhouette_support_missing", про=sorted(ознаки_у_рядку | особа_у_рядку)))
            continue
        описано |= bool(ознаки_у_рядку and (особа_у_рядку or not особисте))
        прийняті.append(рядок)
    if not описано:
        розбіжності.append(dict(чому="silhouette_missing", про=sorted(класи.keys() | особисте)))
    return прийняті, розбіжності
