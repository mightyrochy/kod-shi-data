"""Записи речей нового виду, вкладені в каталог (наряд `Запис-речі-прохід-сцен`, п.4): файл `дані/записи_речей.json.gz` —
{id речі з крамницею: {опис, мітки, модель, зусилля, дата, версія_міток}}, пише його прохід запису речей
за наказом «Запис-речі-прохід-сцен». У режимі «нові» місце з міток стає єдиним полем `слот` рядка,
решту міток і підготовлені мірки крамниці читає `річ.читати` за ключем `мітки_речі`."""
import gzip
import json
from pathlib import Path

from . import місце_речі

ФАЙЛ = Path(__file__).with_name("дані") / "записи_речей.json.gz"
_ЗАПИСИ = None


def записи():
    """Усі записи файла; нема файла — порожньо. Читає раз за процес."""
    global _ЗАПИСИ
    if _ЗАПИСИ is None:
        if ФАЙЛ.exists():
            with gzip.open(ФАЙЛ, "rt", encoding="utf-8") as файл:
                _ЗАПИСИ = json.load(файл)
        else:
            _ЗАПИСИ = {}
    return _ЗАПИСИ


def вкласти(каталог, джерело=None):
    """Вкладає мітки й мірки та переносить вибране місце до єдиного поля рядка ядра.

    `джерело` дає готовий словник записів для тесту. Типове джерело — файл."""
    за_ід = записи() if джерело is None else джерело
    вихід = []
    for рядок in каталог:
        if not isinstance(рядок, dict):
            вихід.append(рядок)
            continue
        ід = рядок.get("id")
        наявний = рядок.get("мітки_речі")
        запис = за_ід.get(ід, наявний)
        слот_каталогу = рядок.get("слот")
        мітки = запис.get("мітки") if isinstance(запис, dict) else None
        слот = місце_речі.з_каталогу(слот_каталогу)
        if слот != слот_каталогу:
            рядок = dict(рядок, слот=слот, джерело_слота="каталог")
        новий = {}
        if isinstance(мітки, dict):
            новий = {"опис": запис.get("опис"), "мітки": {п: м for п, м in мітки.items() if п != "слот"}}
            if isinstance(наявний, dict) and "мірки_крамниці" in наявний:
                новий["мірки_крамниці"] = наявний["мірки_крамниці"]
            if "модель" in запис or "слот" in мітки:
                слот, свідок = місце_речі.із_запису(ід, слот_каталогу, мітки)
                рядок = dict(рядок, слот=слот, джерело_слота=свідок)
        elif isinstance(наявний, dict):
            новий = dict(наявний)
        elif наявний is not None:
            вихід.append(рядок)
            continue
        мірки = рядок.get("мірки_крамниці")
        if мірки or мірки is not None and рядок.get("довжина_виробу_см") is not None:
            новий["мірки_крамниці"] = мірки
        вихід.append(dict(рядок, мітки_речі=новий) if новий else рядок)
    return вихід
