"""Вкладає в рядок каталогу мітки з фото й типізовані факти крамниці.

`дані/записи_речей.json.gz` дає мітки й опис окремого товару за ідентифікатором із крамницею.
Мірки розбирає код каталогу. Обидва джерела читає `річ.читати` з одного вкладеного запису.
"""
import gzip
import json
from pathlib import Path

ФАЙЛ = Path(__file__).with_name("дані") / "записи_речей.json.gz"
_ЗАПИСИ = None


def записи():
    """Усі записи файла; нема файла — порожньо. Читає раз за процес."""
    global _ЗАПИСИ
    if _ЗАПИСИ is None:
        if ФАЙЛ.exists():
            with gzip.open(ФАЙЛ, "rt", encoding="utf-8") as файл:
                _ЗАПИСИ = json.load(файл)
        else:
            _ЗАПИСИ = {}
    return _ЗАПИСИ


def вкласти(каталог, джерело=None):
    """Вкладає в запис нового виду мітки з фото й підготовлені факти крамниці.

    `джерело` — готовий словник записів (тест); без нього — файл."""
    за_ід = записи() if джерело is None else джерело
    вихід = []
    for рядок in каталог:
        if not isinstance(рядок, dict):
            вихід.append(рядок)
            continue
        запис = за_ід.get(рядок.get("id"))
        наявний = рядок.get("мітки_речі")
        if наявний is not None and not isinstance(наявний, dict) and not запис:
            вихід.append(рядок)
            continue
        новий = dict(наявний) if isinstance(наявний, dict) else {}
        if запис:
            новий.update(опис=запис["опис"], мітки={п: м for п, м in запис["мітки"].items() if п != "слот"})
        мірки = рядок.get("мірки_крамниці")
        if мірки or мірки is not None and рядок.get("довжина_виробу_см") is not None:
            новий["мірки_крамниці"] = мірки
        вихід.append(dict(рядок, мітки_речі=новий) if новий else рядок)
    return вихід
