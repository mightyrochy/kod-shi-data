"""Записи речей нового виду, вкладені в каталог (наряд `Запис-речі-прохід-сцен`, п.4): файл `дані/записи_речей.json.gz` —
{id речі з крамницею: {опис, мітки, модель, зусилля, дата, версія_міток}}, пише його прохід запису речей
за наказом «Запис-речі-прохід-сцен». Вкладає перемикач `записи_речі`=«нові» (типово); читає запис той самий
`річ.читати` за ключем `мітки_речі` — другого читача чи словника кольорів нема. Мітку «слот» запис не вкладає: слот речі —
з рядка каталогу (проходом він змінився у 204 із 3004 речей — комплект→низ, сукня→низ тощо; рішення про слот — окреме). Файла нема — каталог лишається як був."""
import gzip
import json
from pathlib import Path

ФАЙЛ = Path(__file__).with_name("дані") / "записи_речей.json.gz"
_ЗАПИСИ = None


def записи():
    """Усі записи файла; нема файла — порожньо. Читає раз за процес."""
    global _ЗАПИСИ
    if _ЗАПИСИ is None:
        if ФАЙЛ.exists():
            with gzip.open(ФАЙЛ, "rt", encoding="utf-8") as файл:
                _ЗАПИСИ = json.load(файл)
        else:
            _ЗАПИСИ = {}
    return _ЗАПИСИ


def вкласти(каталог, джерело=None):
    """Копії рядків каталогу, де в речі є запис, з ключем `мітки_речі`; решта рядків — ті самі об'єкти, без змін.

    `джерело` — готовий словник записів (тест); без нього — файл."""
    за_ід = записи() if джерело is None else джерело
    вихід = []
    for рядок in каталог:
        запис = за_ід.get(рядок.get("id")) if isinstance(рядок, dict) else None
        вихід.append(dict(рядок, мітки_речі={"опис": запис["опис"],
                                              "мітки": {п: м for п, м in запис["мітки"].items() if п != "слот"}}) if запис else рядок)
    return вихід
