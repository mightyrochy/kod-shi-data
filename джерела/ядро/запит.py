    тіло = dict(зміст, заглушка=f"частину пише {НАРЯД}", вид=вид, рука=рука, версія_ситуації=ситуація.версія,
                перемикачі=перемикачі)
    return Запит(ключ=f"р{рука}-{вид}", рука=рука, вид=вид, версія_ситуації=ситуація.версія, сід=пул.сід,
                 модель={"max_tokens": 4000, "messages": [
                     {"role": "user", "content": json.dumps(тіло, ensure_ascii=False, sort_keys=True)}]})
