def _колонки_запису(колонки, речі, повний_пул):
    """Колонки запису речі нового виду стоять у пулі, лише коли хоч одна річ має значення: каталог без них не платить
    токенами за стовпці «unknown»; що правилу бракує входу, каже стан правила. Вільного опису в повному пулі
    (складання, ремонт) нема: кандидат несе коди й мітки, опис читають руки над обраними речами — опис образу, вибір,
    оцінка (рішення менеджера 26.11 по 17183: пул с5 ріс з 86 до 157 тис. токенів)."""
    def відомі(колонка):
        """Читає лише вхід поля, від якого залежить наявність колонки."""
        if колонка == "description":
            return not повний_пул and any(_значення(р.опис) != "unknown" for р in речі)
        поле = _КОЛОНКИ_ЗАПИСУ[колонка]
        return any(_значення(р.поля[поле].значення) != "unknown" for р in речі)

    return tuple(к for к in колонки if к not in _КОЛОНКИ_ЗАПИСУ or відомі(к))
