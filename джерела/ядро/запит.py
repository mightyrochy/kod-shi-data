_ПРОБІЛИ = frozenset(" \t\n\r\v\f\u00a0")


def _несе(в):
    """Чи несе значення щось — та сама міра, що в чинного збирача: None і порожнє — ні; 0 і False — так."""
    if в is None:
        return False
    if isinstance(в, str):
        return any(с not in _ПРОБІЛИ for с in в)
    if isinstance(в, (list, tuple, dict)):
        return bool(в)
    return True


def _вхід_образу(дані):
    """Рядки «input» чинного промпта руки: рядок оголошеного шляху, який у даних непорожній (вкладений теж), чи
    його «без»; той самий рядок — раз. Оголошення — `дані/руки_без_коду.json`, «вхід_образу»."""
    рядки = []
    for п in БЕЗ_КОДУ["вхід_образу"]:
        вузли = [дані]
        for ключ, список in п["шлях"]:
            далі = []
            for в in вузли:
                if isinstance(в, dict) and ключ in в:
                    if not список:
                        далі.append(в[ключ])
                    elif isinstance(в[ключ], (list, tuple)):
                        далі.extend(в[ключ])
            вузли = далі
        рядок = п["рядок"] if any(_несе(в) for в in вузли) else п["без"]
        if рядок and рядок not in рядки:
            рядки.append(рядок)
    return рядки


