def _розмір_повідомлень(текст, фото):
    """JSON.stringify(messages).length для оболонки показу, у кодових одиницях UTF-16."""
    блоки = []
    for ф in фото:
        блоки.append({"type": "text", "text": "Catalogue photo for item " + ф["n"] + ":"})
        блоки.append({"type": "image", "source": {"type": "url", "url": ф["url"]}})
    блоки.append({"type": "text", "text": текст})
    дріт = json.dumps([{"role": "user", "content": блоки}], ensure_ascii=False, separators=(",", ":"))
    return len(дріт.encode("utf-16-le")) // 2


def _під_вікно(тіло, поле_пулу, всі, рядок, групи, закріплені, перевищено, блоки_пулу, черга, кількість_меж):
    """Міряє весь текст і фото із запасом відповіді, зрізає лише додаткових кандидатів."""
    def текст(кандидати):
        номери = tuple(кандидати)
        if поле_пулу:
            тіло[поле_пулу]["rows"] = [рядок(н) for н in номери]
        тіло.update(блоки_пулу(номери))
        return json.dumps(тіло, ensure_ascii=False, separators=(",", ":"))

    @cache
    def дріт_рядка(н):
        """Пам'ятає JSON рядка між пробами квоти."""
        return json.dumps(рядок(н), ensure_ascii=False, separators=(",", ":"))

    def брак_рядків(номери, меж):
        """Зупиняє пробу, якщо вже самі рядки перевищили потрібні межі."""
        дріт = ""
        від, крок = 0, 64
        while від < len(номери):
            # Повне тіло має ті самі знаки рядків і ще оболонку. Міра токенів і UTF-16 монотонні за цими знаками.
            дріт += ("," if дріт else "") + ",".join(дріт_рядка(н) for н in номери[від:від + крок])
            брак = перевищено(дріт)
            if len(брак) >= меж:
                return брак
            від += крок
            крок *= 2
        return ()

    всі = tuple(всі)
    обовʼязкові = tuple(н for н in всі if н in закріплені)
    мінімум = текст(обовʼязкові)
    брак = перевищено(мінімум)
    if брак:
        return мінімум, обовʼязкові, брак
    брак = брак_рядків(всі, кількість_меж) if поле_пулу and кількість_меж else ()
    if not брак:
        повний = текст(всі)
        брак = перевищено(повний)
        if not брак:
            return повний, всі, ()
    черги = [черга(група) for група in групи.values()]
    решта = [н for ряд in zip_longest(*черги) for н in ряд if н is not None and н not in закріплені]
    низ, верх = 0, len(решта)
    while низ < верх:
        середина = (низ + верх + 1) // 2
        вибір = закріплені | set(решта[:середина])
        номери = tuple(н for н in всі if н in вибір)
        if not (поле_пулу and брак_рядків(номери, 1)) and not перевищено(текст(номери)):
            низ = середина
        else:
            верх = середина - 1
    вибір = закріплені | set(решта[:низ])
    номери = tuple(н for н in всі if н in вибір)
    return текст(номери), номери, брак


