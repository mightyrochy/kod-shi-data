def межа_картки(картка, ситуація, *, записи=None, укладка=(), без_фото=None):
    """Нумерує факти готового складу, її ситуації, заяв і свідомих ходів стилістки."""
    межа = Межа(лише_невідоме={"held"}, з_порадами=True, без_адрес_пулу=True)
    номери = {}
    for р in картка.речі:
        рід = СЛОТИ.get(р["слот"], р["слот"])
        описана = р.get("вигадана") is True
        запис = (записи or {}).get(р["н"])
        ознаки = (_річ_для_опису(запис) if запис else
                  {"item_type": р.get("назва"), "details": р.get("деталі")} if описана else {})
        if запис:
            if "sole" not in р.get("опора_опису", {}):
                ознаки.pop("sole", None)
            ознаки["item_type"] = ознаки.pop("type")
            ознаки.pop("kind")
            рядок = _рядок(р["н"], запис, {"за": None})
            ознаки.update({п: рядок[п] for п in ("color", "cut", "pattern", "length", "heel")
                           if рядок[п] not in (None, "unknown")})
        н = межа.предмет(р["ід"] if р["ід"] != р["н"] else None, slot=рід,
                         label=межа.назва_типу(ознаки.get("item_type"), р["слот"]), **ознаки)
        номери[р["н"]] = н
        if запис:
            межа.адреси_речей[р["н"]] = н
        if описана:
            межа.факти[н]["needs_name"] = True
    for поле, значення in ситуація.в_json()["сказала"].items():
        if поле in ("без_поля", "названі_речі") or значення in (None, НЕВІДОМО):
            continue
        if isinstance(значення, dict) and значення.get("значення") == НЕВІДОМО:
            continue
        межа.факт(ВІДОМЕ, dict(field=поле, value=значення))
    for з in картка.заяви_картки:
        н = межа.заява(dict(code=з["код"], values=з["значення"], item_ids=з["речі"]))
        межа.реєстр[з["ід"]] = н
    for заява in (картка.дія_для_вибору or {}).get("statements", ()):
        межа.заява(заява)
    for з in картка.заяви_картки:
        if з.get("назва") and (назва := межа.назва_речі(з["назва"])):
            межа.факти[межа.реєстр[з["ід"]]]["label"] = назва
    for з in картка.свідомі:
        н = межа.реєстр.get(з["заява"])
        межа.факт("stylist_choice", dict(reason=з["чому_en"], finding=н),
                   межа.факти[н].get("items", ()) if н else ())
    for з in укладка:
        н = номери.get(з.get("item"))
        if н:
            межа.факт(ВІДОМЕ, dict(field="way_to_wear", value={к: в for к, в in з.items() if к != "item"}), (н,))
    невідоме = list(картка.невідоме)
    if без_фото:
        код = "description_written_without_photos" if без_фото == "not_delivered" else "description_photos_left_out"
        невідоме.append(dict(код=код, значення={"reason": без_фото}))
    for з in невідоме:
        код = з["код"]
        тема = _ТЕМИ_КАРТКИ.get(з.get("поле")) if код == "item_property_unknown" else _ТЕМИ_КАРТКИ.get(код)
        if not тема:
            continue
        адреси = (з["річ"],) if з.get("річ") else з.get("речі", ())
        речі = [межа.реєстр[і] for і in адреси if і in межа.реєстр]
        з_полем = dict(field=з.get("поле"), slot=СЛОТИ.get(з.get("слот")), values=з.get("значення"))
        if код == "catalogue_slot_shortage":
            тема = "наявність потрібного різновиду речі в каталозі"
        межа.факт("held", dict(code=код, topic=тема, **з_полем), речі)
    return межа


