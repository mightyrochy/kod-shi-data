"""Ч7. Збирає дані показу з перевіреного складу."""
from dataclasses import replace

from .поняття import Картка, Збій, НЕВІДОМО, НЕ_ПЕВНИЙ

НАРЯД = None


def хибні_кадри(опис, пул, кадри):
    """Зберігає свідчення лише про доставлений кадр своєї речі."""
    if isinstance(опис, Збій):
        return set()
    return {(пул.записи[н].ід, кадри[н]) for н in опис.фото_не_те if н in кадри}


def зібрати(образ, вирок, опис, пул, фото_були, прийнято=(), *, хибні=None):
    """Прив'язує речі, заяви та пояснення до одного складу."""
    номери = tuple(р["н"] for р in образ.речі)
    версія = образ.версія_ситуації
    if (вирок.образ, вирок.склад, вирок.версія_ситуації) != (образ.ід, номери, версія):
        return зі_збою(образ.рука, версія, Збій("вирок_не_того_складу", "картка", "вирок", вирок.образ))
    збій_опису = опис if isinstance(опис, Збій) else None
    if збій_опису is None and (опис.образ, опис.склад) != (образ.ід, номери):
        збій_опису = Збій("опис_не_того_складу", "картка", "опис", опис.образ)
    if хибні is None:
        кадри = {н: пул.записи[н].фото[0] for н in фото_були if н in номери and пул.записи[н].фото}
        хибні = хибні_кадри(опис, пул, кадри) if збій_опису is None else set()
    речі = []
    невідоме = []
    for н in номери:
        річ = пул.записи[н]
        речі.append({"н": н, "ід": річ.ід, "слот": річ.слот, "назва": річ.назва,
                     "крамниця": річ.крамниця, "ціна": річ.ціна, "url": річ.url, "фото": річ.фото})
        for поле in ("колір", "каблук", "підошва") if річ.слот == "взуття" else ("колір",):
            if річ.поля[поле].значення in (НЕВІДОМО, НЕ_ПЕВНИЙ):
                невідоме.append({"код": "item_property_unknown", "річ": річ.ід, "поле": поле})
    ціни = [р["ціна"] for р in речі]
    разом = sum(ціни) if all(isinstance(ц, (float, int)) and not isinstance(ц, bool) for ц in ціни) else НЕВІДОМО
    if not фото_були and not збій_опису:
        невідоме.append({"код": "description_written_without_photos"})
    for пункт in пул.нема_в_каталозі:
        невідоме.append({"код": "catalogue_slot_shortage", "слот": пункт["слот"], "є": пункт["є"]})
    заяви = tuple({"ід": з.ід, "код": з.код, "значення": з.значення["факти"],
                   "речі": tuple(пул.записи[н].ід for н in з.речі)}
                  for з in вирок.заяви if з.адресат == "картка")
    свідомі = tuple(з for з in образ.свідомі if з["заява"] in {заява["ід"] for заява in заяви})
    свідомі += tuple({"заява": з["finding"], "чому_en": з["why"]} for з in прийнято)
    return Картка(рука=образ.рука, версія_ситуації=версія, образ=образ.ід, вирок=вирок.образ,
                  речі=tuple(речі), разом=разом, опис_en="" if збій_опису else опис.текст,
                  як_носити_en=() if збій_опису else опис.носіння,
                  фото_не_те=tuple(р["ід"] for р in речі if р["фото"] and (р["ід"], р["фото"][0]) in хибні),
                  заяви_картки=заяви, невідоме=tuple(невідоме), свідомі=свідомі,
                  про_речі_en=() if збій_опису else tuple((пул.записи[н].ід, текст) for н, текст in опис.про_речі),
                  збій_опису=збій_опису.в_json() if збій_опису else None)


def зі_збою(рука, версія, збій):
    """Створює картку-збій цієї руки."""
    return Картка(рука=рука, версія_ситуації=версія, збій=збій)


def на_позиції(картка, позиція):
    """Прив'язує картку до призначеної позиції показу."""
    return replace(картка, позиція=позиція)
