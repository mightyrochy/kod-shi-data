"""Ч7 — дані для картки (`РЕЗУЛЬТАТ.md`, §3 Ч7). Частину пише Н2.

Заглушка Н1 складає `Картка` з обраного образу, вироку над тим самим складом і опису моделі; назви, крамниці,
ціни й фото речей — «невідомо» (запису речі `річ.py` ще нема), а `невідоме` каже, що картка — заглушка ядра.
"""
from dataclasses import replace

from .поняття import Картка, Збій, НЕВІДОМО

НАРЯД = "Н2"


def зібрати(образ, вирок, опис, рука):
    if вирок.образ != образ.ід or вирок.склад != tuple(р["н"] for р in образ.речі):
        return зі_збою(рука, образ.версія_ситуації,
                       Збій(вид="вирок_не_того_складу", частина="картка", поле="вирок", що=вирок.образ))
    return Картка(рука=рука, версія_ситуації=образ.версія_ситуації, образ=образ.ід, вирок=вирок.образ,
                  речі=tuple({"н": р["н"], "ід": р["ід"], "назва": НЕВІДОМО, "крамниця": НЕВІДОМО,
                              "ціна": НЕВІДОМО, "фото": НЕВІДОМО} for р in образ.речі),
                  опис_en=опис["text"], як_носити_en=опис["how_to_wear"], фото_не_те=опис["wrong_photos"],
                  невідоме=(f"заглушка_ядра:{НАРЯД}",))


def зі_збою(рука, версія, збій):
    return Картка(рука=рука, версія_ситуації=версія, збій=збій)


def на_позиції(картка, позиція):
    return replace(картка, позиція=позиція)
