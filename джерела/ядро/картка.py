НАРЯД = None


def хибні_кадри(опис, пул, кадри):
    """Зберігає свідчення лише про доставлений кадр своєї речі."""
    if isinstance(опис, Збій):
        return set()
    return {(пул.записи[н].ід, кадри[н]) for н in опис.фото_не_те if н in кадри}


# Чому опис пішов без кадрів, хоча в складу вони є (руки.`_обмін`): лише «not_delivered» — кадри справді не дійшли
# до моделі; решту кадрів зняло саме ядро, і картка каже про це іншою заявою з причиною, а не «не дійшли»
# (приймання Н2 на 7f5e9d88, знахідка 2).
ПРИЧИНИ_БЕЗ_ФОТО = ("not_delivered", "size_limit", "retry_after_format_error", "retry_after_model_error",
                    "after_failed_swap")


def _рядок_вибору(ситуація, поле, брак, речі):
    вибір = ситуація.сказала["схема"] if ситуація else None
    if not вибір or вибір.джерело not in ("форма", "її_слова"):
        return None
    значення = вибір.значення
    схема = значення if ключ("palette_scheme", значення) else код("palette_scheme", значення)
    if not схема:
        return None
    if поле == "профіль.колір":
        риси = ситуація.риси_портрета or {}
        if any(риси.get(к) for к in ("шкіра", "волосся", "очі", "очі_кільце", ПОЛЕ_ОЦІНКИ_ОЧЕЙ)):
            return повідомлення("card_choice_portrait_colours_incomplete", заява(
                "palette_scheme_portrait_colours_incomplete", scheme=схема))
        return повідомлення("card_choice_missing_input", заява(
            "palette_scheme_needs_portrait", scheme=схема, action="add_portrait"))
    if поле == "палітра.якір_тон":
        return повідомлення("card_choice_anchor_missing", заява("palette_scheme_anchor_missing", scheme=схема))
    if іди := брак.get("речі"):
        предмети = [річ_заяви(dict(id=р["ід"], слот=р["слот"])) for р in речі if р["ід"] in іди]
        return повідомлення("card_choice_item_colour_missing", заява(
            "palette_scheme_item_colour_missing", scheme=схема, item_ids=іди, items=предмети))
    return None


def зібрати(образ, вирок, опис, пул, фото_були, прийнято=(), *, ситуація=None, хибні=None, без_фото=None):
    """Прив'язує речі, заяви та пояснення до одного складу; `без_фото` — причина з `ПРИЧИНИ_БЕЗ_ФОТО` чи None."""
    if без_фото is not None and без_фото not in ПРИЧИНИ_БЕЗ_ФОТО:
        raise ValueError(f"без_фото: {без_фото!r} не з ПРИЧИНИ_БЕЗ_ФОТО")
    номери = tuple(р["н"] for р in образ.речі)
    версія = образ.версія_ситуації
    if not номери or (вирок.образ, вирок.склад, вирок.версія_ситуації) != (образ.ід, номери, версія):
        return зі_збою(образ.рука, версія, Збій("вирок_не_того_складу", "картка", "вирок", вирок.образ))
    збій_опису = опис if isinstance(опис, Збій) else None
    if опис is not None and збій_опису is None and (опис.образ, опис.склад) != (образ.ід, номери):
        збій_опису = Збій("опис_не_того_складу", "картка", "опис", опис.образ)
    if хибні is None:
        кадри = {н: пул.записи[н].фото[0] for н in фото_були if н in номери and пул.записи[н].фото}
        хибні = хибні_кадри(опис, пул, кадри) if опис is not None and збій_опису is None else set()
    речі = []
    невідоме = []
    стан_схеми = вирок.чекліст.get("K-COL-03") or {}
    брак_схеми = вирок.брак_схеми or {}
    бракує_кольору = set(брак_схеми.get("речі", ()))
    бракує = {стан["поле"] for стан in вирок.чекліст.values() if стан["стан"] == "немає_входу"}
    for н in номери:
        річ = пул.записи[н]
        речі.append({"н": н, "ід": річ.ід, "слот": річ.слот, "назва": річ.назва,
                     "крамниця": річ.крамниця, "ціна": річ.ціна, "url": річ.url, "фото": річ.фото,
                     "опора_опису": відоме_для_опису(річ)})
        for поле in ("колір", "каблук", "підошва") if річ.слот == "взуття" else ("колір",):
            якщо_бракує = поле in бракує and річ.поля[поле].значення == НЕВІДОМО
            if якщо_бракує or (поле == "колір" and річ.ід in бракує_кольору):
                невідоме.append({"код": "item_property_unknown", "річ": річ.ід, "поле": поле})
    ціни = [р["ціна"] for р in речі]
    разом = sum(ціни) if all(isinstance(ц, (float, int)) and not isinstance(ц, bool) for ц in ціни) else НЕВІДОМО
    if без_фото and not фото_були and not збій_опису:
        невідоме.append({"код": "description_written_without_photos"} if без_фото == "not_delivered"
                        else {"код": "description_photos_left_out", "причина": без_фото})
    for пункт in пул.нема_в_каталозі:
        невідоме.append({"код": "catalogue_slot_shortage", "слот": пункт["слот"], "є": пункт["є"]})
    заяви = []
    for з in вирок.заяви:
        if з.адресат not in ("картка", "невідоме"):
            continue
        запис = {"ід": з.ід, "код": з.код, "значення": з.значення["факти"], "правило": з.правило,
                 "назва": з.значення.get("назва"),
                 "речі": tuple(пул.записи[н].ід for н in з.речі)}
        for поле in ("вага", "впевненість", "утримано"):
            if з.значення.get(поле) is not None:
                запис[поле] = з.значення[поле]
        if з.адресат == "невідоме" and з.код in ЇЙ_У_НЕПЕРЕВІРЕНОМУ:
            запис["для_жінки"] = True
        (невідоме if з.адресат == "невідоме" else заяви).append(запис)
    дія_для_вибору = None
    if стан_схеми.get("стан") == "немає_входу":
        поле = стан_схеми["поле"]
        дія_для_вибору = _рядок_вибору(ситуація, поле, брак_схеми, речі)
        if поле != "профіль.колір" or not дія_для_вибору:
            невідоме.append({"код": "rule_input_missing", "поле": поле, "правило": "K-COL-03"})
    свідомі = tuple(з for з in образ.свідомі if з["заява"] in {заява["ід"] for заява in заяви})
    свідомі += tuple({"заява": з["finding"], "чому_en": з["why"]} for з in прийнято)
    текст = опис if збій_опису is None else None
    тип = Картка if текст is not None and (текст.текст.strip() or текст.речення) else СкладКартки
    return тип(рука=образ.рука, версія_ситуації=версія, образ=образ.ід, вирок=вирок.образ,
                  речі=tuple(речі), разом=разом, опис_en=текст.текст if текст else "",
                  як_носити_en=текст.носіння if текст else (),
                  фото_не_те=tuple(р["ід"] for р in речі if р["фото"] and (р["ід"], р["фото"][0]) in хибні),
                  заяви_картки=tuple(заяви), невідоме=tuple(невідоме), свідомі=свідомі, дія_для_вибору=дія_для_вибору,
                  про_речі_en=tuple((пул.записи[н].ід, т) for н, т in текст.про_речі) if текст else (),
                  речення=текст.речення if текст else None,
                  збій_опису=збій_опису.в_json() if збій_опису else None)


def зі_збою(рука, версія, збій):
    """Повертає один рядок замість картки, якої рука не дала."""
    return ВідмоваРуки(рука, версія, збій, "Цей образ не вийшов. Спробуй зібрати образи ще раз.")


def на_позиції(картка, позиція):
    """Прив'язує картку до призначеної позиції показу."""
    return replace(картка, позиція=позиція)


def з_реченнями(картка, речення, збій=None):
    """Записує перевірені речення на картку того самого складу."""
    дані = {поле.name: getattr(картка, поле.name) for поле in fields(СкладКартки)}
    дані.update(речення=речення, опис_en="", збій_опису=збій.в_json() if збій else None)
    return Картка(**дані)


def без_коду(образ, вирок, проза):
    """Картка руки 3–4: описані речі без крамниць, цін і фото; вирок і пояснення — про той самий склад."""
    номери = tuple(р["н"] for р in образ.речі)
    if not номери or not проза.strip() or (
        вирок.образ, вирок.склад, вирок.версія_ситуації
    ) != (образ.ід, номери, образ.версія_ситуації):
        return зі_збою(образ.рука, образ.версія_ситуації, Збій("вирок_не_того_складу", "картка", "вирок", вирок.образ))
    return Картка(рука=образ.рука, версія_ситуації=образ.версія_ситуації, образ=образ.ід, вирок=вирок.образ,
                  речі=tuple({"н": р["н"], "ід": р["н"], "слот": р["слот"], "назва": р["назва"],
                              "деталі": р["деталі"], "hex": р["hex"], "вигадана": True} for р in образ.речі),
                  разом=None, опис_en=проза)
