def _блок(де, д, поля, джерела):
    _без_чужих(де, д or {}, поля)
    вихід = {}
    for п, (_опис, вид) in поля.items():
        в = (д or {}).get(п, НЕВІДОМО if вид != "факт" else Факт())
        if вид == "факт":
            в = _факт(в)
            if в.джерело is not None and в.джерело not in джерела:
                raise ХибнеЗначення(f"{де}.{п}: джерело «{в.джерело}» не для цього блоку")
        elif в != НЕВІДОМО:
            в = tuple(е if isinstance(е, вид) else вид.з_json(е) for е in в)
            for е in в:
                if getattr(е, "джерело", None) not in джерела:
                    raise ХибнеЗначення(f"{де}.{п}: джерело «{е.джерело}» не для цього блоку")
        вихід[п] = в
    return вихід


@dataclass(frozen=True)
class Ситуація(_Поняття):
    """Її день: `сказала` (лише її слова й тапи) і `виведено` (дата, код, норма події, стилістка). Пише Ч1."""
    ПИСАЧ = "перекладач_паспорта"
    _ДЖЕРЕЛА_СКАЗАЛА = ДЖЕРЕЛА_СКАЗАЛА
    _ДЖЕРЕЛА_ВИВЕДЕНО = ДЖЕРЕЛА_ВИВЕДЕНО
    версія: int
    сказала: dict = field(default_factory=dict)
    виведено: dict = field(default_factory=dict)

    def __post_init__(self):
        _версія("Ситуація", self.версія)
        object.__setattr__(self, "сказала", _блок("Ситуація.сказала", self.сказала, ПОЛЯ_СКАЗАЛА, self._ДЖЕРЕЛА_СКАЗАЛА))
        object.__setattr__(self, "виведено", _блок("Ситуація.виведено", self.виведено, ПОЛЯ_ВИВЕДЕНО,
                                                   self._ДЖЕРЕЛА_ВИВЕДЕНО))


