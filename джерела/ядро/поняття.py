"""Поняття нового ядра шляху образу — одне визначення кожного (`РЕЗУЛЬТАТ.md`, §3 «Спільне»; `ОПИС.md`, розділ 0).

Кожне поняття — `dataclass` з одним конструктором із JSON (`з_json`) і одним перетворенням у JSON (`в_json`).
Чужий ключ — помилка `ЧужийКлюч` з назвою ключа, а не мовчазна втрата (Т1). Кожен вихід шляху (пул, запит, образ,
вирок, вибір, картка) несе `версія_ситуації` — номер версії `Ситуації`, з якої він зроблений (Т35). Значення факту —
`Факт{значення, джерело}`; «невідомо» — окреме значення, джерела «типове» нема. `ПИСАЧ` кожного поняття — єдиний
модуль ядра, що його складає (сторож будови в `тести/тест_будова.py`); `Збій` пише будь-яка частина.
"""
from collections.abc import Mapping
from types import MappingProxyType
from dataclasses import dataclass, field, fields

НЕВІДОМО = "невідомо"
НЕ_ПЕВНИЙ = "не_певний"
ДЖЕРЕЛА_СКАЗАЛА = frozenset({"її_слова", "форма"})
ДЖЕРЕЛА_ВИВЕДЕНО = frozenset({"дата", "код", "норма_події", "стилістка"})
ДЖЕРЕЛА = ДЖЕРЕЛА_СКАЗАЛА | ДЖЕРЕЛА_ВИВЕДЕНО | {"крамниця", "фото", "модель_каталогу"}
СТАНИ_ЧЕКЛІСТА = frozenset({"суджено", "немає_входу", "нема_чого"})


class ЧужийКлюч(KeyError):
    """Ключ, якого нема в описі поняття: записати його неможливо (Т1)."""

    def __init__(self, де, ключ):
        super().__init__(f"{де}: чужий ключ «{ключ}»")
        self.ключ = ключ

    def __str__(self):
        return self.args[0]


class ХибнеЗначення(ValueError):
    """Значення не за договором поняття (джерело, уривок, версія, стан чекліста)."""


def _без_чужих(де, д, дозволені):
    if not isinstance(д, dict):
        raise ХибнеЗначення(f"{де}: очікувано об'єкт, а не {type(д).__name__}")
    for к in д:
        if к not in дозволені:
            raise ЧужийКлюч(де, к)


def _в_json(з):
    if isinstance(з, _Поняття):
        return {п.name: _в_json(getattr(з, п.name)) for п in fields(з)}
    if isinstance(з, Mapping):
        return {к: _в_json(в) for к, в in з.items()}
    if isinstance(з, (list, tuple)):
        return [_в_json(в) for в in з]
    return з


class _Поняття:
    ПИСАЧ = None
    _ВКЛАДЕНІ = {}

    @classmethod
    def з_json(кл, д):
        _без_чужих(кл.__name__, д, {п.name for п in fields(кл)})
        return кл(**{к: кл._ВКЛАДЕНІ.get(к, lambda в: в)(в) for к, в in д.items()})

    def в_json(self):
        return _в_json(self)


def _версія(де, в):
    if not isinstance(в, int) or isinstance(в, bool) or в < 1:
        raise ХибнеЗначення(f"{де}: версія_ситуації — ціле ≥ 1, а не {в!r}")


@dataclass(frozen=True)
class Факт(_Поняття):
    """Значення з джерелом. `її_слова` — лише з уривком; `код` і `норма_події` — з переліком `з_чого`."""
    _ДЖЕРЕЛА = ДЖЕРЕЛА
    значення: object = НЕВІДОМО
    джерело: str = None
    уривок: str = None
    з_чого: tuple = ()
    межі: object = None

    def __post_init__(self):
        object.__setattr__(self, "з_чого", tuple(self.з_чого))
        if self.значення == НЕВІДОМО:
            if self.джерело is not None:
                raise ХибнеЗначення("Факт: «невідомо» не має джерела")
            return
        if self.джерело not in self._ДЖЕРЕЛА:
            raise ХибнеЗначення(f"Факт: джерело {self.джерело!r} не з переліку")
        if self.джерело == "її_слова" and not self.уривок:
            raise ХибнеЗначення("Факт: джерело «її_слова» без уривка")
        if self.джерело in ("код", "норма_події") and not self.з_чого:
            raise ХибнеЗначення(f"Факт: джерело «{self.джерело}» без «з_чого»")
        if self.значення == НЕ_ПЕВНИЙ and self.межі is None:
            raise ХибнеЗначення("Факт: «не_певний» без меж")


def _факт(в):
    return в if isinstance(в, Факт) else Факт.з_json(в)


