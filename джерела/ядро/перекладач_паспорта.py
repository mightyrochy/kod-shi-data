"""Тимчасовий вхід зі старого паспорта. Н4 замінює його Ситуацією з розмови."""
from dataclasses import InitVar, dataclass

from . import знання
from .поняття import Етап, НазванаРіч, Ситуація, Факт, НЕВІДОМО

_ДЖЕРЕЛО = "паспорт"


class _ФактПаспорта(Факт):
    _ДЖЕРЕЛА = Факт._ДЖЕРЕЛА | {_ДЖЕРЕЛО}


@dataclass(frozen=True)
class _СитуаціяПаспорта(Ситуація):
    _ДЖЕРЕЛА_СКАЗАЛА = Ситуація._ДЖЕРЕЛА_СКАЗАЛА | {_ДЖЕРЕЛО}
    _ДЖЕРЕЛА_ВИВЕДЕНО = Ситуація._ДЖЕРЕЛА_ВИВЕДЕНО | {_ДЖЕРЕЛО}
    план: InitVar[dict | None] = None

    def __post_init__(self, план):
        super().__post_init__()
        object.__setattr__(self, "план_палітри", план)


_СКАЗАЛА = {
    "подія": ("нагода", "occasion"), "роль": ("роль", "role"),
    "місяць": ("місяць", "month"), "день_тижня": ("день_тижня", "weekday"),
    "смуга_погоди": ("смуга_погоди", "weather_band"),
    "опади": ("опади", "precipitation"), "ошатність": ("ступінь_ошатності", "ошатність", "formality"),
    "рух": ("рух", "movement"), "пішки_хв": ("дорога_пішки_хв", "walk_min"),
    "поверхня": ("поверхня", "surface"), "тривалість": ("тривалість_год", "duration_hours"),
    "відмови": ("жорстке_ні", "відмови"), "схема": ("схема", "scheme"),
    "бажання": ("бажання", "wishes"),
}
_ВИВЕДЕНО = {
    "пора_року": ("пора", "season"), "смуга_ошатності": ("смуга_ошатності", "formality_band"),
    "чужий_колір": ("зарезервований_колір", "reserved_colour"),
    "світло": ("світло", "light"), "сіль": ("сіль", "salt"), "палітра_дня": ("палітра_дня",),
}


def _значення(дані, *ключі):
    """Бере наявне закодоване значення паспорта."""
    for ключ in ключі:
        значення = дані.get(ключ)
        if значення not in (None, "", НЕВІДОМО, "unknown"):
            return значення
    return НЕВІДОМО


def _факт(значення, джерело=_ДЖЕРЕЛО):
    """Позначає факт джерелом старого паспорта."""
    return (_ФактПаспорта(значення, джерело) if значення != НЕВІДОМО else Факт())


def підготувати_палітру(вхід):
    """Дає виробнику ті самі поля портрета й вибору, які вже везе ВХІД-V1."""
    профіль = вхід.get("профіль") or {}
    колір = профіль.get("колір") or {}
    if not колір:
        return None
    палітра = профіль.get("палітра") or {}
    мірки = профіль.get("мірки") or {}
    паспорт = вхід.get("паспорт") or {}
    return знання.палітрові_знання().палітра_для_ядра({
        "шкіра": колір.get("шкіра"), "волосся": колір.get("волосся"), "очі": колір.get("очі"),
        "очі_кільце": колір.get("кільце"), "портрет_вимір": колір.get("вимір"),
        "гілка": палітра.get("гілка"), "схема": палітра.get("схема"),
        "вибір_кольору": палітра.get("вибір_кольору"), "драп_сирий": профіль.get("драп"),
        "зріст": мірки.get("зріст"), "обхвати": мірки.get("обхвати") or {},
        "аксесуарні": мірки.get("аксесуарні"),
        "сценарій": профіль.get("сценарій"), "паспорт": паспорт, "намір": паспорт.get("намір"),
        "сід": вхід.get("сід"),
    })


def з_входу(вхід, *, план_палітри=None):
    """Повертає поточні факти й один етап зі старого паспорта."""
    дані = вхід.get("паспорт") or {}
    сказала = {поле: _факт(_значення(дані, *ключі)) for поле, ключі in _СКАЗАЛА.items()}
    форма = (вхід.get("профіль") or {}).get("сценарій") or {}
    поля_мети = ("мета", "мета_важливо", "мета_зони")
    if any(ключ in дані or ключ in форма for ключ in поля_мети):
        нагода, паспорт = знання.палітрові_знання().мета_для_ядра(форма, дані)
        for ключ in поля_мети:
            джерело = _ДЖЕРЕЛО if паспорт.get(ключ) not in (None, "", [], НЕВІДОМО) else "форма"
            сказала[ключ] = _факт(_значення(нагода, ключ), джерело)
    етап = Етап("", місце=_значення(дані, "місце", "place"),
                надворі=_значення(дані, "надворі", "outdoors"),
                частина_дня=_значення(дані, "частина_дня", "part_of_day"), джерело=_ДЖЕРЕЛО)
    сказала["етапи"] = (етап,)
    намір = _значення(дані, "намір", "intent")
    if намір != НЕВІДОМО:
        сказала["намір"] = (_факт(намір),)
    названі = дані.get("названі_речі")
    if isinstance(названі, list):
        сказала["названі_речі"] = tuple(
            НазванаРіч("", що=_значення(рядок, "тип", "type"), крамниця=_значення(рядок, "крамниця"),
                       колір=_значення(рядок, "колір"), матеріал=_значення(рядок, "матеріал"),
                       її_річ=_значення(рядок, "її_річ"), джерело=_ДЖЕРЕЛО)
            for рядок in названі if isinstance(рядок, dict))
    виведено = {поле: _факт(_значення(дані, *ключі)) for поле, ключі in _ВИВЕДЕНО.items()}
    if план_палітри:
        виведено["палітра_дня"] = Факт(план_палітри["дані"], "код", з_чого=("профіль.колір", "профіль.палітра"))
    return _СитуаціяПаспорта(вхід.get("версія", 1), сказала, виведено, план=план_палітри)
