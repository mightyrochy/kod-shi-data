def факт(ситуація, поле):
    """Читає факт із цілої Ситуації."""
    return ситуація.сказала.get(поле, ситуація.виведено.get(поле, Факт()))


def _наявне(факт):
    """Відрізняє закодоване значення від невідомого й непевного."""
    return факт.значення not in (НЕВІДОМО, НЕ_ПЕВНИЙ)


def _смуга(значення):
    """Бере нижній і верхній щаблі інтервалу."""
    if isinstance(значення, (list, tuple)) and len(значення) == 2:
        if all(isinstance(щабель, (int, float)) for щабель in значення):
            return tuple(значення)
    if isinstance(значення, (int, float)) and not isinstance(значення, bool):
        return значення, значення
    return None


def _відмова(річ, відмови):
    """Виконує закодовані абсолютні відмови."""
    if not isinstance(відмови, dict):
        return None
    for поле in ("тип", "тканина", "візерунок", "підошва"):
        значення = річ.поля[поле]
        заборони = відмови.get(поле) or ()
        if _наявне(значення) and значення.значення in заборони:
            return поле
    каблук = річ.поля["каблук"]
    if річ.слот == "взуття" and відмови.get("без_підборів") and _наявне(каблук) and каблук.значення > 0:
        return "каблук"
    return None


def _смуга_нагоди(ситуація, прогін=None):
    """Бере засвідчену смугу або окремий щабель нагоди; зламаний K-KOH-02 цілиться в сусідній щабель."""
    смуга = (_смуга(факт(ситуація, "смуга_ошатності").значення)
             or _смуга(факт(ситуація, "ошатність").значення))
    return знання.злам("K-KOH-02", "смуга", смуга, прогін) if смуга is not None else None


def _межа(річ, відмови, рівень, погода, буденні, прогін):
    """Відкидає запис лише за відомою межею."""
    if річ.збої:
        return "запис", "bad_record"
    if річ.слот not in СЛОТИ:
        return "слот", "unsupported_kind"
    відмова = _відмова(річ, відмови)
    if відмова:
        return "її_відмова", відмова
    ошатність = _смуга(річ.поля["ошатність"].значення)
    тип = річ.поля["тип"].значення
    if рівень and ошатність and isinstance(тип, str) and тип in буденні:
        if рівень[0] - ошатність[1] >= ДОБІР["відрив_рівня"]:
            return "явно_чуже", "below_event_level"
    if погода not in (НЕВІДОМО, НЕ_ПЕВНИЙ):
        сезон = річ.поля["сезон_тканини"].значення
        if isinstance(сезон, (tuple, list)) and сезон:
            from verify import поза_смугою_тканини
            відстань = поза_смугою_тканини(сезон, погода)
            if відстань is not None:
                справне = "fabric_off_temperature" if відстань > ДОБІР["допуск_погоди"] else None
                причина = знання.злам("K-MAT-03", "пул", справне, прогін, поза=відстань,
                                      допуск=ДОБІР["допуск_погоди"], слот=річ.слот)
                if причина:
                    return "K-MAT-03", причина
        if річ.слот == "взуття" and isinstance(тип, str) and тип != НЕВІДОМО:
            from accessory import відстань_смуг, смуга_типу
            смуга = смуга_типу(тип)
            відстань = відстань_смуг(смуга, погода) if смуга is not None else None
            if відстань is not None and відстань > ДОБІР["допуск_погоди"]:
                return "K-SHO-16", "shoes_off_temperature"
    return None


def _за(річ, ситуація):
    """Знаходить причину за точними кодами побажання."""
    названі = ситуація.сказала["названі_речі"]
    if названі == НЕВІДОМО:
        return None
    for названа in названі:
        if названа.що != НЕВІДОМО and названа.що == річ.поля["тип"].значення:
            if названа.крамниця in (НЕВІДОМО, річ.крамниця):
                return {"code": "her_wish", "source": "код", "from": ("named_items", "type")}
    return None


def _смілива(річ):
    """Розпізнає закодований візерунок або виразний реєстр."""
    візерунок = річ.поля["візерунок"]
    реєстр = річ.поля["реєстр"].значення
    return (_наявне(візерунок) and візерунок.значення != "solid"
            or реєстр in ("editorial", "statement", "fashion_forward"))


def _ряд(речі, слот):
    """Чередує окремі роди прикрас по черзі, зберігаючи порядок кожного."""
    if слот not in ДОБІР["прикраси"]:
        return речі
    метал, колір = [], []
    for річ in речі:
        (метал if річ.поля["метал"].джерело else колір).append(річ)
    return [річ for пара in zip_longest(метал, колір) for річ in пара if річ is not None]


def _ранг_нагоди(річ, смуга):
    """Повертає мітку нижчої смуги і відстань канонічних інтервалів."""
    if смуга is None:
        return False, 0
    межі = _смуга(річ.поля["ошатність"].значення)
    if межі is None:
        return False, 0.5
    низ, верх = смуга
    відстань = max(низ - межі[1], межі[0] - верх, 0)
    if межі[1] >= низ:
        return False, відстань

    from формальність import ФОРМА_ЗАПАС, ЩАБЕЛЬ, типи_форми, щабель_смуги

    щабель = щабель_смуги(низ)
    тип = річ.поля["тип"].значення
    форма = (isinstance(тип, str) and тип in типи_форми(щабель)
             and межі[1] >= ЩАБЕЛЬ[щабель]["смуга"][0] - ФОРМА_ЗАПАС)
    return not форма, відстань


def _пізні_чинники(ситуація, профіль, прогін=None):
    """Читає штатні ранги за її метою, ярусом тіла й довжиною шару."""
    сцен = знання.день_правил(ситуація)
    мета = сцен.get("мета")
    зони = сцен.get("мета_зони")
    тіло = профіль or {}
    if not (мета or зони or тіло.get("зріст")):
        return lambda р: ((0, 1, 0), {})

    from hypergraph import крої_для_пулу, ТИПОВИЙ_НАМІР
    from місце_речі import ярус
    from регістр_уваги import ранг_уваги
    from верхнє_довжина import нижче_коліна, ранг_пулу

    крої = крої_для_пулу(тіло, intent=сцен.get("intent") or ТИПОВИЙ_НАМІР, прогін_руки=прогін) or {}
    сила = ранг_пулу(тіло, сцен.get("смуга_погоди"))
    from крої_ранг import _ранг_крою, причина_рангу_крою

    def чинники(річ):
        запис = знання.старий_запис(річ)
        увага = ранг_уваги(запис, мета, слот=річ.слот, зони_мети=зони)
        ярус_тіла = крої.get(ярус(запис))
        крій = _ранг_крою(запис, ярус_тіла)
        причина = причина_рангу_крою(запис, ярус_тіла) if ярус_тіла else None
        підстави = {}
        if увага:
            підстави["attention_rank"] = увага
        if причина:
            підстави["cut"] = причина
        довгий = None
        if сила and річ.слот == "верхній_шар":
            довгий, джерело = нижче_коліна(запис, тіло.get("висоти"))
            підстави["length"] = {"below_knee": довгий, "source": джерело}
        return (увага, крій, int(довгий is True)), підстави

    return чинники


