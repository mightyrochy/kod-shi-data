def _влучання(запис, колір, вікна):
    """Найближче сумісне вікно найранішої доступної хвилі для однієї речі."""
    from добір_за_вікнами import влучає
    from feed import відстань_до_центру, описує_річ

    кращий = None
    for вікно, ключ in вікна:
        if колір[1] and not описує_річ(запис, вікно, вікно=колір[1]):
            continue
        частка = влучає(запис, вікно, колір, ключ)
        if not частка:
            continue
        відстань = (1.0 - частка) * 100 if колір[1] else відстань_до_центру(колір[2], вікно)
        збіг = (вікно.get("спроба", 0), відстань, частка if колір[1] else None)
        if кращий is None or збіг[:2] < кращий[:2]:
            кращий = збіг
    return кращий


def _палітра(ситуація, каталог):
    """Дає гілку як свідчення конкретної речі з пулу без складання образів кодом."""
    from добір_за_вікнами import колір_речі
    from feed import відстань_до_центру
    from місце_речі import бік_межі
    from palettes import метал_речі
    from реєстр_намір import сміливі_наміри

    план = ситуація.план_палітри or {}
    if not план.get("вікна") or not каталог:
        return {}
    основні = _вікна_за_слотом(план["вікна"])
    межові = _вікна_за_слотом(план.get("вікна_межі", ()))
    вікна_слотів = {}
    наміри = ситуація.сказала["намір"]
    сміливо = наміри != НЕВІДОМО and наміри and наміри[-1].значення in сміливі_наміри()
    факти, розриви = {}, defaultdict(list)
    збіги, відстані = {}, {}
    for ід, запис in каталог.items():
        слот = запис["слот"]
        колір = колір_речі(запис)
        if слот not in вікна_слотів:
            вікна = (*основні[слот], *основні[None])
            інші = (*межові[слот], *межові[None])
            вікна_слотів[слот] = вікна, інші, any(в.get("метал") for в, _ in (*вікна, *інші))
        вікна, інші, є_метал = вікна_слотів[слот]
        # Для однакового кольору в одному слоті збіг повторюється. Металеве вікно читає ще тон матеріалу.
        ключ_кольору = (слот, колір[3], колір[2])
        ключ = (*ключ_кольору, метал_речі(запис) if є_метал else None)
        if ключ not in збіги:
            збіг = _влучання(запис, колір, вікна)
            збіги[ключ] = ((збіг, "ядро") if збіг is not None else
                           (_влучання(запис, колір, інші), "на межі"))
        збіг, гілка = збіги[ключ]
        if збіг is not None:
            хвиля, відстань, частка = збіг
            факти[ід] = {"branch": гілка, "wave": хвиля}
            if math.isfinite(відстань):
                факти[ід]["distance"] = відстань
            if частка is not None:
                факти[ід]["window_share"] = частка
        elif сміливо and колір[0] and бік_межі(запис) is False and вікна:
            if ключ_кольору not in відстані:
                відстані[ключ_кольору] = min(відстань_до_центру(запис, в) for в, _ in (*вікна, *інші))
            розриви[слот].append((відстані[ключ_кольору], ід))
    # «Розрив» — вибір моделі в речах далеко від обличчя. Перший слот лише позначає приклад із найбільшою
    # відстанню від видимих вікон, без пробного складання образів.
    основний_розрив = max(розриви, key=lambda слот: max(розриви[слот]), default=None)
    for слот, ряд in розриви.items():
        for відстань, ід in ряд:
            факти[ід] = {"branch": "розрив", "distance": відстань, "primary_break": слот == основний_розрив}
    return факти


def _дозована_група(група, квота, ранги, сід):
    """Обмежує склад групи спільним добором, зберігаючи її порядок для показу."""
    if len(група) <= квота:
        return група, []
    обрані = set(добрати({р.ід: ранги[р.ід] for р in група}, квота, сід))
    return ([р for р in група if р.ід in обрані], [р for р in група if р.ід not in обрані])


def _вибрати_з_палітри(ряди, за, палітра, ранги, сід):
    """Лишає підтверджене ядро, дозу інших гілок і доступний запас до підлоги."""
    from переплести_ряди import переплести

    вихід, причини = {}, {}
    межа_дози = ДОБІР["сміливих"][1]
    for слот, ряд in ряди.items():
        закріплені, запас, гілки = [], [], defaultdict(list)
        for річ in ряд:
            гілка = палітра.get(річ.ід, {}).get("branch")
            if річ.ід in за:
                закріплені.append(річ)
            elif гілка:
                гілки[гілка].append(річ)
            else:
                запас.append(річ)
        for гілка, група in гілки.items():
            if гілка != "ядро":
                гілки[гілка], відсіяні = _дозована_група(група, межа_дози, ранги, сід)
                причини.update((р.ід, "palette_dose") for р in відсіяні)
        відібрані = закріплені + переплести(гілки.values())
        взяти_запас = max(0, _ПІДЛОГА - len(відібрані))
        резерв, відсіяні = _дозована_група(запас, взяти_запас, ранги, сід)
        вихід[слот] = _ряд(відібрані + резерв, слот)
        причини.update((р.ід, "outside_palette_selection") for р in відсіяні)
    return вихід, причини


def черга_слота(кандидати, номери, сід):
    """Впорядковує номери одного слота для зрізу вже сформованого пулу."""
    ранги = {н: кандидати[н].get("_ранг_добору", ()) for н in номери}
    return добрати(ранги, len(ранги), сід)


def _ранг(річ, за, сід, палітра, ранги):
    """Ранжує за побажанням, вікном, нагодою, пізніми правилами й сідом."""
    вікно = палітра.get(річ.ід, {})
    гілка = вікно.get("branch")
    відстань = вікно.get("distance", 0)
    колір = ({"ядро": 0, "на межі": 1, "розрив": 2}.get(гілка, 3),
             вікно.get("wave", 0), -відстань if гілка == "розрив" else відстань)
    відбиток = blake2s(f"{сід}:{річ.ід}".encode(), digest_size=8).digest()
    return (річ.ід not in за, *колір, *ранги[річ.ід], відбиток, річ.ід)


def _скільки_треба(ситуація, слоти):
    """Визначає обов'язкові види з наявних слотів і відомої погоди."""
    подія = факт(ситуація, "подія").значення
    треба = ["shoes"] if подія not in ("home", "sport", "вдома", "спорт") and слоти["взуття"] else []
    смуга = факт(ситуація, "смуга_погоди").значення
    if слоти["верхній_шар"] and смуга != НЕВІДОМО:
        from суд_погода import пальтова_смуга
        if пальтова_смуга(смуга):
            треба.append("outerwear")
    return tuple(треба)


def зібрати(ситуація, рука, сід, каталог, бюджет=НЕВІДОМО, *, профіль=None, зламані=()):
    """Призначає кожному запису місце в пулі або названу причину відсіву.

    `зламані` — поломки руки 2 значенням на вході: ті самі межі й ранги, але зламане правило хибить там, де діє."""
    прогін = знання.прогін_поломок(зламані)
    ряди, за, відкинуто = defaultdict(list), {}, []
    допущені = {}
    лічба_меж = defaultdict(Counter)
    невідомі = Counter()
    для_погоди = факт(ситуація, "смуга_погоди").значення
    відмови = факт(ситуація, "відмови").значення
    смуга = _смуга_нагоди(ситуація, прогін)
    буденні = ()
    if смуга is not None:
        from формальність import типи_нижче_межі
        буденні = типи_нижче_межі(ДОБІР["рівень_буденності"])
    for рядок in каталог:
        річ = читати(рядок)
        межа = _межа(річ, відмови, смуга, для_погоди, буденні, прогін)
        if межа:
            назва, причина = межа
            відкинуто.append({"ід": річ.ід, "межа": назва, "причина": причина,
                             "заяви": tuple(з.в_json() for з in річ.збої)})
            лічба_меж[річ.слот][причина] += 1
            continue
        ряди[річ.слот].append(річ)
        допущені[річ.ід] = рядок
        причина_за = _за(річ, ситуація)
        if причина_за is not None:
            за[річ.ід] = причина_за
        if для_погоди in (НЕВІДОМО, НЕ_ПЕВНИЙ):
            невідомі["смуга_погоди"] += 1
        elif not _наявне(річ.поля["сезон_тканини"]):
            невідомі["сезон_тканини"] += 1
        if not _наявне(річ.поля["ошатність"]):
            невідомі["ошатність"] += 1

    палітра = _палітра(ситуація, допущені)
    чинники = _пізні_чинники(ситуація, профіль, прогін)
    пізні = {р.ід: чинники(р) for ряд in ряди.values() for р in ряд}

    ранги = {р.ід: (*_ранг_нагоди(р, смуга), *пізні[р.ід][0]) for ряд in ряди.values() for р in ряд}

    def ранг(річ):
        """Зберігає порядок показу пулу після добору."""
        return _ранг(річ, за, сід, палітра, ранги)
    ряди = {слот: _ряд(sorted(ряди[слот], key=ранг), слот)
            for слот in СЛОТИ}
    if палітра:
        ряди, причини = _вибрати_з_палітри(ряди, за, палітра, ранги, сід)
    else:
        # Без палітрових свідчень діє попередня доза за відомим візерунком і реєстром.
        сміливі = sorted((р for ряд in ряди.values() for р in ряд if _смілива(р)), key=ранг)
        межа_дози = ДОБІР["сміливих"][1]
        квоти = Counter(р.слот for р in сміливі[:межа_дози] if р.ід not in за)
        групи = defaultdict(list)
        for річ in сміливі:
            if річ.ід not in за:
                групи[річ.слот].append(річ)
        понад_дозу = {}
        for слот, група in групи.items():
            _, відсіяні = _дозована_група(група, квоти[слот], ранги, сід)
            понад_дозу.update((р.ід, "bold_dose") for р in відсіяні)
        ряди = {слот: [р for р in ряд if р.ід not in понад_дозу] for слот, ряд in ряди.items()}
        причини = понад_дозу
    for ід, причина in причини.items():
        відкинуто.append({"ід": ід, "межа": "палітра_або_доза", "причина": причина})
        лічба_меж[допущені[ід]["слот"]][причина] += 1
    межі_слотів = {СЛОТИ[слот]: 1 for слот in СЛОТИ}
    записи, рядки, слоти, нестача = {}, [], {}, []
    сміливих = 0
    for номер_слота, (слот, ряд) in enumerate(ряди.items(), 1):
        у_слоті = 0
        for позиція, річ in enumerate(ряд, 1):
            гілка = палітра.get(річ.ід, {}).get("branch")
            смілива = (гілка in ("на межі", "розрив")) if палітра else _смілива(річ)
            н = f"#{позиція}·{номер_слота:02d}"
            сміливих += смілива
            у_слоті += 1
            записи[н] = річ
            рядки.append({"н": н, "ід": річ.ід, "ранг": позиція, "_ранг_добору": ранги[річ.ід],
                          "джерело_рангу": (ДОБІР["джерела"]["порядок"], ДОБІР["джерела"]["ранг_нагоди"])
                          if смуга is not None else (ДОБІР["джерела"]["порядок"],), "за": за.get(річ.ід),
                          "факти_рангу": {**палітра.get(річ.ід, {}), **пізні[річ.ід][1]}})
        слоти[слот] = у_слоті
        if у_слоті < _ПІДЛОГА:
            причини = dict(лічба_меж[слот]) or {"catalogue_supply": len(ряд)}
            нестача.append({"слот": слот, "є": у_слоті, "підлога": _ПІДЛОГА, "причина": причини})
    return Пул(рука=рука, сід=сід, версія_ситуації=ситуація.версія, речі=tuple(рядки), слоти=слоти,
               відкинуто=tuple(відкинуто), нема_в_каталозі=tuple(нестача), сміливих=сміливих, бюджет=бюджет,
               записи=записи, обовʼязкові=_скільки_треба(ситуація, слоти), межі_слотів=межі_слотів,
               невідомі_межі=tuple({"поле": поле, "скільки": n} for поле, n in невідомі.items()))


# Турнір (перемикач «вибір», В-1): група — до 10 речей слота, з групи модель називає 2 переможців; слот, де речей не
# більше, ніж переможців, груп не має — його речі проходять у фінал самі.
ГРУПА_ТУРНІРУ = 10
ПЕРЕМОЖЦІВ = 2


def групи_турніру(пул, сід):
    """Пул → {«вид-k»: (номери)}: речі слота перемішано сідом руки й поділено на рівні групи по ≤ `ГРУПА_ТУРНІРУ`;
    ключ — вид кодом дроту, його модель бачить і пише у відповіді. Слот із ≤ `ПЕРЕМОЖЦІВ` речами груп не має."""
    за_слотом = {}
    for р in пул.речі:
        за_слотом.setdefault(пул.записи[р["н"]].слот, []).append(р["н"])
    групи = {}
    for слот, номери in за_слотом.items():
        if len(номери) <= ПЕРЕМОЖЦІВ:
            continue
        номери = sorted(номери, key=lambda н: blake2s(f"{сід}|tournament|{слот}|{н}".encode(), digest_size=8).digest())
        к = -(-len(номери) // ГРУПА_ТУРНІРУ)
        розмір, лишок, поч = len(номери) // к, len(номери) % к, 0
        for і in range(к):
            кін = поч + розмір + (1 if і < лишок else 0)
            групи[f"{СЛОТИ[слот]}-{і + 1}"] = tuple(номери[поч:кін])
            поч = кін
    return групи


def частини(пул, скільки, дозволені=None):
    """Пул частинами (перемикач «частин», К-3 «варіант Б»): номери речей кожної частини.

    Речі кожного слота розходяться по частинах по черзі, тим самим порядком, що в пулі; слот, у якому речей менше, ніж
    частин, іде в кожну частину цілим — щоб кожна частина могла скласти повний образ. Одна частина — весь пул.
    `дозволені` (фінал турніру чи оцінки) — ділиться лише він, тим самим правилом."""
    речі = [р for р in пул.речі if дозволені is None or р["н"] in дозволені]
    if скільки <= 1:
        return (frozenset(р["н"] for р in речі),)
    за_слотом = {}
    for р in речі:
        за_слотом.setdefault(пул.записи[р["н"]].слот, []).append(р["н"])
    вих = [set() for _ in range(скільки)]
    for номери in за_слотом.values():
        for і, н in enumerate(номери):
            for ч in (range(скільки) if len(номери) < скільки else (і % скільки,)):
                вих[ч].add(н)
    return tuple(frozenset(ч) for ч in вих)
