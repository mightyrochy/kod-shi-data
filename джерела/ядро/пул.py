from . import знання
from .поняття import Пул, Факт, НЕВІДОМО, НЕ_ПЕВНИЙ
from .річ import читати

НАРЯД = "Н3"
with Path(__file__).with_name("дані").joinpath("добір.json").open(encoding="utf-8") as _файл:
    ДОБІР = json.load(_файл)
СЛОТИ = ДОБІР["слоти"]
_ПІДЛОГА = ДОБІР["підлога"]


def факт(ситуація, поле):
    """Читає факт із цілої Ситуації."""
    return ситуація.сказала.get(поле, ситуація.виведено.get(поле, Факт()))


def _наявне(факт):
    """Відрізняє закодоване значення від невідомого й непевного."""
    return факт.значення not in (НЕВІДОМО, НЕ_ПЕВНИЙ)


def _смуга(значення):
    """Бере нижній і верхній щаблі інтервалу."""
    if isinstance(значення, (list, tuple)) and len(значення) == 2:
        if all(isinstance(щабель, (int, float)) for щабель in значення):
            return tuple(значення)
    if isinstance(значення, (int, float)) and not isinstance(значення, bool):
        return значення, значення
    return None


def _відмова(річ, відмови):
    """Виконує закодовані абсолютні відмови."""
    if not isinstance(відмови, dict):
        return None
    for поле in ("тип", "тканина", "візерунок", "підошва"):
        значення = річ.поля[поле]
        заборони = відмови.get(поле) or ()
        if _наявне(значення) and значення.значення in заборони:
            return поле
    каблук = річ.поля["каблук"]
    if річ.слот == "взуття" and відмови.get("без_підборів") and _наявне(каблук) and каблук.значення > 0:
        return "каблук"
    return None


def _смуга_нагоди(ситуація):
    """Бере засвідчену смугу або окремий щабель нагоди."""
    return (_смуга(факт(ситуація, "смуга_ошатності").значення)
            or _смуга(факт(ситуація, "ошатність").значення))


def _межа(річ, подія, буденні):
    """Відкидає запис лише за відомою межею."""
    if річ.збої:
        return "запис", "bad_record"
    if річ.слот not in СЛОТИ:
        return "слот", "unsupported_kind"
    відмова = _відмова(річ, факт(подія, "відмови").значення)
    if відмова:
        return "її_відмова", відмова
    рівень = _смуга_нагоди(подія)
    ошатність = _смуга(річ.поля["ошатність"].значення)
    тип = річ.поля["тип"].значення
    if рівень and ошатність and isinstance(тип, str) and тип in буденні:
        if рівень[0] - ошатність[1] >= ДОБІР["відрив_рівня"]:
            return "явно_чуже", "below_event_level"
    погода = факт(подія, "смуга_погоди").значення
    if погода not in (НЕВІДОМО, НЕ_ПЕВНИЙ):
        сезон = річ.поля["сезон_тканини"].значення
        if isinstance(сезон, (tuple, list)) and сезон:
            from verify import поза_смугою_тканини
            відстань = поза_смугою_тканини(сезон, погода)
            if відстань is not None and відстань > ДОБІР["допуск_погоди"]:
                return "K-MAT-03", "fabric_off_temperature"
        if річ.слот == "взуття" and isinstance(тип, str) and тип != НЕВІДОМО:
            from accessory import відстань_смуг, смуга_типу
            смуга = смуга_типу(тип)
            відстань = відстань_смуг(смуга, погода) if смуга is not None else None
            if відстань is not None and відстань > ДОБІР["допуск_погоди"]:
                return "K-SHO-16", "shoes_off_temperature"
    return None


def _за(річ, ситуація):
    """Знаходить причину за точними кодами побажання."""
    названі = ситуація.сказала["названі_речі"]
    if названі == НЕВІДОМО:
        return None
    for названа in названі:
        if названа.що != НЕВІДОМО and названа.що == річ.поля["тип"].значення:
            if названа.крамниця in (НЕВІДОМО, річ.крамниця):
                return {"code": "her_wish", "source": "код", "from": ("named_items", "type")}
    return None


def _смілива(річ):
    """Розпізнає закодований візерунок або виразний реєстр."""
    візерунок = річ.поля["візерунок"]
    реєстр = річ.поля["реєстр"].значення
    return (_наявне(візерунок) and візерунок.значення != "solid"
            or реєстр in ("editorial", "statement", "fashion_forward"))


def _ряд(речі, слот):
    """Чередує окремі роди прикрас по черзі, зберігаючи порядок кожного."""
    if слот not in ДОБІР["прикраси"]:
        return речі
    метал, колір = [], []
    for річ in речі:
        (метал if річ.поля["метал"].джерело else колір).append(річ)
    return [річ for пара in zip_longest(метал, колір) for річ in пара if річ is not None]


def _ранг_нагоди(річ, смуга):
    """Повертає мітку нижчої смуги і відстань канонічних інтервалів."""
    if смуга is None:
        return False, 0
    межі = _смуга(річ.поля["ошатність"].значення)
    if межі is None:
        return False, 0.5
    низ, верх = смуга
    відстань = max(низ - межі[1], межі[0] - верх, 0)
    if межі[1] >= низ:
        return False, відстань

    from формальність import ФОРМА_ЗАПАС, ЩАБЕЛЬ, типи_форми, щабель_смуги

    щабель = щабель_смуги(низ)
    тип = річ.поля["тип"].значення
    форма = (isinstance(тип, str) and тип in типи_форми(щабель)
             and межі[1] >= ЩАБЕЛЬ[щабель]["смуга"][0] - ФОРМА_ЗАПАС)
    return not форма, відстань


def _пізні_чинники(ситуація, профіль):
    """Читає штатні ранги за її метою, ярусом тіла й довжиною шару."""
    сцен = знання.старий_сценарій(ситуація)
    мета = сцен.get("мета")
    зони = сцен.get("мета_зони")
    тіло = профіль or {}
    if not (мета or зони or тіло.get("зріст")):
        return lambda р: ((0, 1, 0), {})

    from композитор_слоти import _ранг_крою, причина_рангу_крою
    from hypergraph import крої_для_пулу, ТИПОВИЙ_НАМІР
    from місце_речі import ярус
    from регістр_уваги import ранг_уваги
    from верхнє_довжина import нижче_коліна, ранг_пулу

    крої = крої_для_пулу(тіло, intent=сцен.get("intent") or ТИПОВИЙ_НАМІР) or {}
    сила = ранг_пулу(тіло, сцен.get("смуга_погоди"))

    def чинники(річ):
        запис = знання.старий_запис(річ)
        увага = ранг_уваги(запис, мета, слот=річ.слот, зони_мети=зони)
        ярус_тіла = крої.get(ярус(запис))
        крій = _ранг_крою(запис, ярус_тіла)
        підстави = {}
        if увага:
            підстави["attention_rank"] = увага
        if ярус_тіла:
            підстави["cut"] = причина_рангу_крою(запис, ярус_тіла)
        довгий = None
        if сила and річ.слот == "верхній_шар":
            довгий, джерело = нижче_коліна(запис, тіло.get("висоти"))
            підстави["length"] = {"below_knee": довгий, "source": джерело}
        return (увага, крій, int(довгий is True)), підстави

    return чинники


def _палітра(ситуація):
    """Читає готові вікна того самого пакета, коли вони дійшли до Н2."""
    дані = факт(ситуація, "палітра_дня").значення
    ядро = дані.get("_запити_у_фід") if isinstance(дані, dict) else None
    if not ядро:
        return lambda р: {}
    from композитор_реєстр import ГІЛКА_ЯДРО, ГІЛКА_МЕЖА, ГІЛКА_РОЗРИВ, СМІЛИВІ_НАМІРИ
    from композитор_слоти import влучає, колір_речі
    from feed import відстань_до_центру, влучає_метал, описує_річ
    from місце_речі import бік_межі

    сміливий = знання.старий_сценарій(ситуація).get("intent") in СМІЛИВІ_НАМІРИ
    інші = дані.get("вікна_на_межі") if сміливий else None
    слот_розриву = (дані.get("розрив") or {}).get("слот") if інші is not None else None

    def вікна_слота(вікна, слот):
        return [q for q in (вікна or ()) if isinstance(q, dict) and q.get("слот") in (None, "", слот)
                and q.get("L_min") is not None]

    def чинники(річ):
        основні = вікна_слота(ядро, річ.слот)
        межа = вікна_слота(інші, річ.слот)
        if not (основні or межа):
            return {}
        запис = знання.старий_запис(річ)
        метал = річ.поля["метал"]
        if метал.межі and метал.джерело:
            запис["метал"] = метал.межі
        межі, вікно, точка, ключ = колір_речі(запис)
        for гілка, вікна in ((ГІЛКА_ЯДРО, основні), (ГІЛКА_МЕЖА, межа)):
            збіги = []
            for q in вікна:
                м = влучає_метал(запис, q)
                if м is not None:
                    if м:
                        збіги.append((q.get("спроба") or 0, 0.0, None))
                    continue
                if гілка == ГІЛКА_ЯДРО and вікно and not описує_річ(запис, q, вікно=вікно):
                    continue
                частка = влучає(запис, q, (межі, вікно, точка, ключ))
                if частка:
                    відстань = (1.0 - частка) * 100.0 if вікно else відстань_до_центру(точка, q)
                    збіги.append((q.get("спроба") or 0, відстань, частка if вікно else None))
            if збіги:
                хвиля, відстань, частка = min(збіги, key=lambda з: з[:2])
                return {"branch": гілка, "distance": відстань, "wave": хвиля, "window_share": частка}
        if (межі and слот_розриву == річ.слот and бік_межі(запис) is False
                and not any(влучає(запис, q, (межі, вікно, точка, ключ)) for q in основні + межа)):
            відстань = min(відстань_до_центру(запис, q) for q in основні + межа)
            return {"branch": ГІЛКА_РОЗРИВ, "distance": відстань}
        return {}

    return чинники


def _ранг(річ, за, сід, смуга, палітра, пізні):
    """Ранжує за побажанням, вікном, нагодою, пізніми правилами й сідом."""
    вікно = палітра[річ.ід]
    гілка = вікно.get("branch")
    відстань = вікно.get("distance", 0)
    колір = ({"ядро": 0, "на межі": 1, "розрив": 2}.get(гілка, 3),
             вікно.get("wave", 0), -відстань if гілка == "розрив" else відстань)
    відбиток = blake2s(f"{сід}:{річ.ід}".encode(), digest_size=8).digest()
    return (річ.ід not in за, *колір, *_ранг_нагоди(річ, смуга), *пізні[річ.ід][0], відбиток, річ.ід)


def _скільки_треба(ситуація, слоти):
    """Визначає обов'язкові види з наявних слотів і відомої погоди."""
    подія = факт(ситуація, "подія").значення
    треба = ["shoes"] if подія not in ("home", "sport", "вдома", "спорт") and слоти["взуття"] else []
    смуга = факт(ситуація, "смуга_погоди").значення
    if слоти["верхній_шар"] and смуга != НЕВІДОМО:
        from суд_погода import пальтова_смуга
        if пальтова_смуга(смуга):
            треба.append("outerwear")
    return tuple(треба)


def зібрати(ситуація, рука, сід, каталог, бюджет=НЕВІДОМО, *, профіль=None):
    """Призначає кожному запису місце в пулі або названу причину відсіву."""
    ряди, за, відкинуто = defaultdict(list), {}, []
    лічба_меж = defaultdict(Counter)
    невідомі = Counter()
    для_погоди = факт(ситуація, "смуга_погоди").значення
    смуга = _смуга_нагоди(ситуація)
    буденні = ()
    if смуга is not None:
        from формальність import типи_нижче_межі
        буденні = типи_нижче_межі(ДОБІР["рівень_буденності"])
    for рядок in каталог:
        річ = читати(рядок)
        межа = _межа(річ, ситуація, буденні)
        if межа:
            назва, причина = межа
            відкинуто.append({"ід": річ.ід, "межа": назва, "причина": причина,
                             "заяви": tuple(з.в_json() for з in річ.збої)})
            лічба_меж[річ.слот][причина] += 1
            continue
        ряди[річ.слот].append(річ)
        причина_за = _за(річ, ситуація)
        if причина_за is not None:
            за[річ.ід] = причина_за
        if для_погоди in (НЕВІДОМО, НЕ_ПЕВНИЙ):
            невідомі["смуга_погоди"] += 1
        elif not _наявне(річ.поля["сезон_тканини"]):
            невідомі["сезон_тканини"] += 1
        if not _наявне(річ.поля["ошатність"]):
            невідомі["ошатність"] += 1

    колір, чинники = _палітра(ситуація), _пізні_чинники(ситуація, профіль)
    палітра = {р.ід: колір(р) for ряд in ряди.values() for р in ряд}
    пізні = {р.ід: чинники(р) for ряд in ряди.values() for р in ряд}

    def ранг(річ):
        return _ранг(річ, за, сід, смуга, палітра, пізні)

    ряди = {слот: _ряд(sorted(ряди[слот], key=ранг), слот)
            for слот in СЛОТИ}
    сміливі = [р for ряд in ряди.values() for р in ряд if _смілива(р)]
    низ, верх = ДОБІР["сміливих"]
    сміливі = sorted(сміливі, key=ранг)
    резерв = {р.ід for р in сміливі[:низ]}
    узяті = резерв | set(за)
    сміливих = sum(р.ід in узяті for р in сміливі)
    for ряд in ряди.values():
        ліміт = max(0, _ПІДЛОГА - sum(р.ід in узяті for р in ряд))
        for річ in ряд:
            if not ліміт:
                break
            смілива = _смілива(річ)
            if річ.ід in узяті or смілива and сміливих >= верх:
                continue
            узяті.add(річ.ід)
            сміливих += смілива
            ліміт -= 1
        if ліміт:
            узяті.update([р.ід for р in ряд if р.ід not in узяті][:ліміт])
    межі_слотів = {СЛОТИ[слот]: 1 for слот in СЛОТИ}
    записи, рядки, слоти, нестача = {}, [], {}, []
    сміливих = 0
    for номер_слота, (слот, ряд) in enumerate(ряди.items(), 1):
        у_слоті = 0
        for позиція, річ in enumerate(ряд, 1):
            смілива = _смілива(річ)
            if річ.ід not in узяті:
                відкинуто.append({"ід": річ.ід, "межа": "обсяг_пулу", "причина": "behind_slot_rank"})
                continue
            н = f"#{позиція}·{номер_слота:02d}"
            сміливих += смілива
            у_слоті += 1
            записи[н] = річ
            рядки.append({"н": н, "ід": річ.ід, "ранг": позиція,
                          "джерело_рангу": (ДОБІР["джерела"]["порядок"], ДОБІР["джерела"]["ранг_нагоди"])
                          if смуга is not None else (ДОБІР["джерела"]["порядок"],), "за": за.get(річ.ід),
                          "факти_рангу": {**палітра[річ.ід], **пізні[річ.ід][1]}})
        слоти[слот] = у_слоті
        if у_слоті < _ПІДЛОГА:
            причини = dict(лічба_меж[слот]) or {"catalogue_supply": len(ряд)}
            нестача.append({"слот": слот, "є": у_слоті, "підлога": _ПІДЛОГА, "причина": причини})
    return Пул(рука=рука, сід=сід, версія_ситуації=ситуація.версія, речі=tuple(рядки), слоти=слоти,
               відкинуто=tuple(відкинуто), нема_в_каталозі=tuple(нестача), сміливих=сміливих, бюджет=бюджет,
               записи=записи, обовʼязкові=_скільки_треба(ситуація, слоти), межі_слотів=межі_слотів,
               невідомі_межі=tuple({"поле": поле, "скільки": n} for поле, n in невідомі.items()))
