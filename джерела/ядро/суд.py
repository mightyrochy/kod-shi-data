"""Ч6. Вирок над одним складом і перевірка незалежного модельного вибору."""
from collections import Counter
from dataclasses import replace
import json

from . import знання
from .поняття import Вирок, Вибір, Заява, Збій

НАРЯД = None


def вхід_складу(образ):
    """Порівнює речі й спосіб їх носіння, який читають правила."""
    речі = frozenset(р["н"] for р in образ.речі)
    носіння = {р["item"]: р for р in образ.носіння}
    return речі, json.dumps(носіння, sort_keys=True, ensure_ascii=False)


def той_самий_склад(вирок, образ):
    """Прив'язує вже обчислені заяви до ідентичного входу іншого образу."""
    if isinstance(вирок, Збій):
        return replace(вирок, поле=образ.ід)
    заяви = tuple(replace(з, ід=f"f-{образ.ід}-{і}") for і, з in enumerate(вирок.заяви, 1))
    return replace(вирок, образ=образ.ід, склад=tuple(р["н"] for р in образ.речі), заяви=заяви)


def судити(образ, ситуація, пул, профіль, зламані=(), *, слід_поломки=None):
    """Судить рівно склад образу з тією самою версією Ситуації."""
    if образ.версія_ситуації != ситуація.версія or пул.версія_ситуації != ситуація.версія:
        return Збій("застаріла_версія", "суд", "версія_ситуації")
    склад = tuple(р["н"] for р in образ.речі)
    речі = tuple(пул.записи[н] for н in склад)
    try:
        стани, брак_схеми = знання.стани_правил_і_брак_схеми(ситуація, речі, профіль)
        пункти = знання.стани_чекліста(ситуація, речі, профіль, стани)
        входи = знання.правила_чекліста(стани, пункти)
        сирі = tuple(знання.заяви(образ, ситуація, речі, профіль, входи, рядки_пулу=пул.речі, пункти=пункти,
                                  зламані=зламані, слід_поломки=слід_поломки))
    except (ValueError, TypeError, KeyError, IndexError, AttributeError) as помилка:
        return Збій("суд_не_відбувся", "суд", образ.ід, f"{type(помилка).__name__}: {помилка}")
    заяви = []
    for і, (правило, код, номери, дані) in enumerate(сирі, 1):
        адресат = "невідоме" if дані.get("утримано") else "картка"
        заяви.append(Заява(ід=f"f-{образ.ід}-{і}", код=код, значення=дані,
                           речі=номери, правило=правило, адресат=адресат))
    лічба = Counter(з.правило for з in заяви)
    гілки = Counter((з.правило, з.значення.get("гілка")) for з in заяви)
    чекліст = {код: (dict(стан, результат=лічба[код]) if стан["стан"] == "суджено" else стан)
               for код, стан in стани.items()}
    чекліст.update(знання.чекліст(пункти, лічба, гілки))
    return Вирок(образ=образ.ід, версія_ситуації=ситуація.версія, склад=склад,
                 заяви=tuple(заяви), чекліст=чекліст, брак_схеми=брак_схеми)


def потребує_ремонту(вирок):
    """Використовує адресний ремонт чи регістр гейта старого суду."""
    return any(not з.значення.get("утримано") and (з.значення["ремонт"] or з.значення["регістр"] == "гейт")
               for з in вирок.заяви)


def вибір(дані, образи, вироки, версія):
    """Приймає лише запропонований моделлю образ і його заяви."""
    обраний = next((о for о in образи if о.номер == дані["chosen"]), None)
    if обраний is None:
        return Збій("схема", "суд", "chosen", f"{дані['chosen']} is not an offered outfit")
    відомі = {з.ід for з in вироки[обраний.ід].заяви if not з.значення.get("утримано")}
    прийнято = tuple(дані.get("accept", ()))
    if any(з["finding"] not in відомі for з in прийнято):
        return Збій("схема", "суд", "accept", "finding is not from the chosen outfit")
    if дані.get("remove"):
        return Збій("схема", "суд", "remove", "composition changes belong to repair")
    return Вибір(обрано=обраний.ід, версія_ситуації=версія, чому_en=дані.get("why", ""), прийнято=прийнято)


def без_коду(образ, ситуація):
    """Вирок руки 3–4: коду й каталогу в неї нема, тож кожен пункт чекліста — «немає входу: каталог», заяв нема."""
    if образ.версія_ситуації != ситуація.версія:
        return Збій("застаріла_версія", "суд", "версія_ситуації")
    return Вирок(образ=образ.ід, версія_ситуації=ситуація.версія, склад=tuple(р["н"] for р in образ.речі),
                 чекліст={f"{група}.{пункт}": {"стан": "немає_входу", "поле": "каталог"}
                          for група, пункти in знання.ЧЕКЛІСТИ.items() for пункт in пункти})
