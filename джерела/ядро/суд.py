"""Ч6. Вирок над одним складом і перевірка незалежного модельного вибору."""
from collections import Counter

from . import знання
from .поняття import Вирок, Вибір, Заява, Збій

НАРЯД = "Н5"


def судити(образ, ситуація, пул, профіль):
    """Судить рівно склад образу з тією самою версією Ситуації."""
    if образ.версія_ситуації != ситуація.версія or пул.версія_ситуації != ситуація.версія:
        return Збій("застаріла_версія", "суд", "версія_ситуації")
    склад = tuple(р["н"] for р in образ.речі)
    речі = tuple(пул.записи[н] for н in склад)
    стани = знання.стан_правил(ситуація, речі, профіль)
    try:
        сирі = tuple(знання.заяви(образ, ситуація, речі, профіль, стани))
    except (ValueError, TypeError, KeyError, IndexError, AttributeError) as помилка:
        return Збій("суд_не_відбувся", "суд", образ.ід, f"{type(помилка).__name__}: {помилка}")
    заяви = []
    for і, (правило, код, значення, номери, ремонт, регістр) in enumerate(сирі, 1):
        поля = {"факти": значення, "ремонт": ремонт, "регістр": регістр}
        заяви.append(Заява(ід=f"f-{образ.номер}-{і}", код=код, значення=поля,
                           речі=номери, правило=правило, адресат="картка"))
    лічба = Counter(з.правило for з in заяви)
    чекліст = {код: (dict(стан, результат=лічба[код]) if стан["стан"] == "суджено" else стан)
               for код, стан in стани.items()}
    чекліст.update(знання.чекліст(стани, лічба))
    return Вирок(образ=образ.ід, версія_ситуації=ситуація.версія, склад=склад,
                 заяви=tuple(заяви), чекліст=чекліст)


def потребує_ремонту(вирок):
    """Використовує адресний ремонт чи регістр гейта старого суду."""
    return any(з.значення["ремонт"] or з.значення["регістр"] == "гейт" for з in вирок.заяви)


def вибір(дані, образи, вироки, версія):
    """Приймає лише запропонований моделлю образ і його заяви."""
    обраний = next((о for о in образи if о.номер == дані["chosen"]), None)
    if обраний is None:
        return Збій("схема", "суд", "chosen", f"{дані['chosen']} is not an offered outfit")
    відомі = {з.ід for з in вироки[обраний.ід].заяви}
    прийнято = tuple(дані.get("accept", ()))
    if any(з["finding"] not in відомі for з in прийнято):
        return Збій("схема", "суд", "accept", "finding is not from the chosen outfit")
    if дані.get("remove"):
        return Збій("схема", "суд", "remove", "composition changes belong to repair")
    return Вибір(обрано=обраний.ід, версія_ситуації=версія, чому_en=дані.get("why", ""), прийнято=прийнято)
