def з_профілем(ситуація, план, риси):
    """Та сама версія її дня з планом палітри й рисами портрета з профілю (до JSON не входять)."""
    return Ситуація(ситуація.версія, ситуація.сказала, ситуація.виведено, план=план, риси=риси)


def тап(ситуація, поле, значення, дата):
    """Тап плитки — та сама `Ситуація` з джерелом `форма`, нова версія; новіше сильніше й для плитки (П5, Т8)."""
    сказала = dict(ситуація.сказала)
    if поле in ("місце", "частина_дня", "надворі"):
        етапи = list(сказала["етапи"]) if сказала["етапи"] != НЕВІДОМО else [Етап("", джерело="форма")]
        перший = етапи[0].в_json()
        перший[поле] = значення
        if перший["джерело"] == "її_слова" and перший[поле] != getattr(етапи[0], поле):
            перший.update(джерело="форма", уривок="")
        етапи[0] = Етап.з_json(перший)
        сказала["етапи"] = tuple(етапи)
    elif поле in ПОЛЯ_СКАЗАЛА and ПОЛЯ_СКАЗАЛА[поле][1] == "факт":
        сказала[поле] = Факт(значення, "форма")
    else:
        raise ХибнеЗначення(f"тап: поля {поле!r} плитка не пише")
    return скласти(ситуація.версія + 1, сказала, дата, палітра_дня=ситуація.виведено["палітра_дня"])


