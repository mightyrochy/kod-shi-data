_АПОСТРОФИ = {"'": "ʼ", "’": "ʼ", "`": "ʼ"}


def уривок_її(уривок, репліки):
    """Чи стоїть уривок дослівно, суцільним рядом цілих слів, хоч в одній її репліці (шматок слова — не її слово).

    Єдина функція ядра над рядками її слів, і це не тлумачення: точна лічба збігу (сторож будови — виняток за
    назвою цієї функції). Значення з уривка код не виводить; чи значення з нього випливає, судить суддя (§5.1)."""
    def слова(текст):  # цілі слова в нижньому регістрі: літери, цифри й апостроф; решта — межа слова
        вихід, поточне = [], []
        for знак in текст.casefold() + " ":
            знак = _АПОСТРОФИ.get(знак, знак)
            if знак.isalnum() or знак == "ʼ":
                поточне.append(знак)
            elif поточне:
                вихід.append("".join(поточне))
                поточне = []
        return вихід

    шукане = слова(уривок) if isinstance(уривок, str) else []
    if not шукане:
        return False
    for репліка in репліки:
        її = слова(репліка)
        for і in range(len(її) - len(шукане) + 1):
            if її[і:і + len(шукане)] == шукане:
                return True
    return False


def її_репліки(репліки):
    """Тексти її реплік — єдине, проти чого звіряють уривки (репліки стилістки — не її слова)."""
    return tuple(р["текст"] for р in репліки or () if р.get("хто") == "вона" and isinstance(р.get("текст"), str))


class _НеЗаСхемою(Exception):
    def __init__(self, вид, поле, що):
        super().__init__(що)
        self.вид, self.поле, self.що = вид, поле, що


def _уривок(д, поле, її):
    уривок = д.get("quote") if isinstance(д, dict) else None
    if not isinstance(уривок, str) or not уривок:
        raise _НеЗаСхемою("схема", поле, "quote is required")
    if not уривок_її(уривок, її):
        raise _НеЗаСхемою("уривок_не_її", поле, f"quote is not her verbatim words: {уривок!r}")
    return уривок


def _без_чужих(д, дозволені, де):
    if not isinstance(д, dict):
        raise _НеЗаСхемою("схема", де, "expected an object")
    for ключ in д:
        if ключ not in дозволені:
            raise _НеЗаСхемою("схема", f"{де}.{ключ}" if де else ключ, "unknown key")


def _код(значення, перелік, поле):
    if значення not in перелік:
        raise _НеЗаСхемою("схема", поле, f"value {значення!r} is not in the list")
    return значення


def _значення_факту(д, опис, поле):
    вид, в = опис["вид"], д.get("value")
    if вид == "перелік":
        return _код(в, опис["значення"], поле)
    if вид == "список":
        if not isinstance(в, list) or not в:
            raise _НеЗаСхемою("схема", поле, "expected a non-empty list")
        return tuple(_код(е, опис["значення"], поле) for е in в)
    if вид == "число":
        if isinstance(в, bool) or not isinstance(в, (int, float)) or в < 0:
            raise _НеЗаСхемою("схема", поле, "expected a nonnegative number")
        return в
    if not (isinstance(в, dict) and set(в) == {"from", "to"}
            and all(type(в[к]) is int and 1 <= в[к] <= 10 for к in в) and в["from"] <= в["to"]):
        raise _НеЗаСхемою("схема", поле, "expected {from, to} steps 1–10")
    return (в["from"], в["to"])


def _етап(д, її, поле):
    _без_чужих(д, ("place", "outdoors", "part_of_day", "quote"), поле)
    місце = _код(д["place"], СХЕМА["етап"]["place"], f"{поле}.place") if "place" in д else НЕВІДОМО
    частина = (_код(д["part_of_day"], СХЕМА["етап"]["part_of_day"], f"{поле}.part_of_day")
               if "part_of_day" in д else НЕВІДОМО)
    надворі = д.get("outdoors", НЕВІДОМО)
    if надворі not in (True, False, НЕВІДОМО):
        raise _НеЗаСхемою("схема", f"{поле}.outdoors", "expected true or false")
    return Етап(_уривок(д, поле, її), місце=місце, надворі=надворі, частина_дня=частина)


def _річ(д, її, поле):
    _без_чужих(д, ("type", "name", "shop", "colour", "fabric", "hers", "quote"), поле)
    р = СХЕМА["річ"]
    уривок = _уривок(д, поле, її)
    for ключ in ("name", "shop"):  # власну назву й крамницю код не тлумачить: лише дослівні її слова
        if ключ in д and not уривок_її(д[ключ], її):
            raise _НеЗаСхемою("уривок_не_її", f"{поле}.{ключ}", f"{ключ} is not her verbatim words")
    return НазванаРіч(уривок,
                      що=_код(д["type"], р["item_type"], f"{поле}.type") if "type" in д else НЕВІДОМО,
                      назва=д.get("name", НЕВІДОМО), крамниця=д.get("shop", НЕВІДОМО),
                      колір=_код(д["colour"], р["color_name"], f"{поле}.colour") if "colour" in д else НЕВІДОМО,
                      матеріал=_код(д["fabric"], р["fabric"], f"{поле}.fabric") if "fabric" in д else НЕВІДОМО,
                      її_річ={"yes": True, "no": False}[_код(д["hers"], р["hers"], f"{поле}.hers")]
                      if "hers" in д else НЕВІДОМО)


def _відмови(список, її):
    межі, уривки = {}, []
    for і, д in enumerate(список):
        поле = f"refusals[{і}]"
        _без_чужих(д, ("kind", "value", "quote"), поле)
        опис = СХЕМА["відмови"].get(д.get("kind"))
        if опис is None:
            raise _НеЗаСхемою("схема", f"{поле}.kind", f"kind {д.get('kind')!r} is not in the list")
        код = _код(д.get("value"), опис["значення"], f"{поле}.value")
        уривки.append(_уривок(д, поле, її))
        if опис["межа"] == "ознака" and код == "heels":
            межі["без_підборів"] = True
        else:
            межі.setdefault(опис["межа"], [])
            if код not in межі[опис["межа"]]:
                межі[опис["межа"]].append(код)
    return межі, tuple(уривки)


def розібрати(текст, репліки):
    """Відповідь розмови → нові факти цього ходу `{поле: значення}` або `_НеЗаСхемою` з видом і полем."""
    try:
        д = json.loads(текст)
    except (TypeError, ValueError) as п:
        raise _НеЗаСхемою("схема", None, f"not JSON: {п}") from п
    _без_чужих(д, ("facts", "stages", "refusals", "wishes", "named_items", "unplaced"), "")
    її = її_репліки(репліки)
    нове = {}
    факти = д.get("facts") or {}
    _без_чужих(факти, СХЕМА["факти"], "facts")
    for ключ, ф in факти.items():
        опис, поле = СХЕМА["факти"][ключ], f"facts.{ключ}"
        _без_чужих(ф, ("value", "quote"), поле)
        значення = _значення_факту(ф, опис, поле)
        нове[опис["поле"]] = Факт(значення, "її_слова", _уривок(ф, поле, її))
    if "stages" in д:
        if not isinstance(д["stages"], list) or not д["stages"]:
            raise _НеЗаСхемою("схема", "stages", "expected a non-empty list")
        нове["етапи"] = tuple(_етап(е, її, f"stages[{і}]") for і, е in enumerate(д["stages"]))
    if д.get("refusals"):
        межі, уривки = _відмови(д["refusals"], її)
        нове["відмови"] = Факт(межі, "її_слова", уривки)
    if д.get("wishes"):
        нове["бажання"] = Факт(tuple(_код(ш.get("value"), СХЕМА["річ"]["item_type"], f"wishes[{і}].value")
                                     for і, ш in enumerate(д["wishes"])), "її_слова",
                               tuple(_уривок(ш, f"wishes[{і}]", її) for і, ш in enumerate(д["wishes"])))
    if д.get("named_items"):
        нове["названі_речі"] = tuple(_річ(р, її, f"named_items[{і}]") for і, р in enumerate(д["named_items"]))
    if д.get("unplaced"):
        нове["без_поля"] = tuple(БезПоля(_уривок({"quote": у}, f"unplaced[{і}]", її))
                                 for і, у in enumerate(д["unplaced"]))
    return нове


def _злити(було, нове):
    """Новий хід доповнює: поля, яких він не стосується, лишаються; про те саме поле новіше сильніше (П5)."""
    сказала = dict(було)
    for поле, в in нове.items():
        if поле in _СПИСКОВІ:
            попередні = () if сказала.get(поле, НЕВІДОМО) == НЕВІДОМО else сказала[поле]
            сказала[поле] = tuple(ф for ф in попередні if ф.значення != в.значення) + (в,)
        elif поле in ("названі_речі", "без_поля"):
            попередні = () if сказала.get(поле, НЕВІДОМО) == НЕВІДОМО else сказала[поле]
            уже = {е.уривок for е in в}
            сказала[поле] = tuple(е for е in попередні if е.уривок not in уже) + в
        elif поле == "відмови" and isinstance(сказала.get(поле), Факт) and сказала[поле].джерело:
            межі = {к: list(з) if isinstance(з, (list, tuple)) else з for к, з in сказала[поле].значення.items()}
            for к, з in в.значення.items():
                межі[к] = з if not isinstance(з, list) else межі.get(к, []) + [к_ for к_ in з if к_ not in межі.get(к, [])]
            уривки = сказала[поле].уривок if isinstance(сказала[поле].уривок, tuple) else (сказала[поле].уривок,)
            сказала[поле] = Факт(межі, "її_слова", уривки + tuple(у for у in в.уривок if у not in уривки))
        else:
            сказала[поле] = в
    return сказала


def _виведено(сказала, дата):
    """Що код рахує функціями знань: лише в `виведено`, з джерелом і полями, з яких виведено."""
    from occasion import вечірнє_світло
    from сценарій import ПОРА_РОКУ_МІСЯЦЯ, сіль_на_дорозі
    from формальність import смуга_ошатності
    import внутрішня_мова as ВМ

    в = {}
    знач = lambda п: getattr(сказала.get(п), "значення", НЕВІДОМО)  # noqa: E731
    місяці = {код: номер for номер, код in enumerate(ВМ.ТАБЛИЦЯ["month"], 1)}
    пори = {ключ: код for код, ключ in ВМ.ТАБЛИЦЯ["season"].items()}
    if знач("місяць") in місяці:
        в["пора_року"] = Факт(пори[ПОРА_РОКУ_МІСЯЦЯ[місяці[знач("місяць")]]], "код", з_чого=("місяць",))
    elif isinstance(дата, str) and len(дата) >= 7 and дата[5:7].isdigit() and 1 <= int(дата[5:7]) <= 12:
        в["пора_року"] = Факт(пори[ПОРА_РОКУ_МІСЯЦЯ[int(дата[5:7])]], "дата")
    етапи = сказала.get("етапи", НЕВІДОМО)
    частина = етапи[0].частина_дня if етапи not in (НЕВІДОМО, ()) else НЕВІДОМО
    if частина != НЕВІДОМО:
        в["світло"] = Факт("evening" if вечірнє_світло(частина) else "daylight", "код", з_чого=("етапи.частина_дня",))
    if знач("ошатність") != НЕВІДОМО:
        сцен = {"ошатність": list(знач("ошатність"))}
        if частина != НЕВІДОМО:
            сцен["пора"] = частина
        смуга = смуга_ошатності(сцен)
        if смуга:
            в["смуга_ошатності"] = Факт([смуга[0], смуга[1]], "код",
                                        з_чого=("ошатність",) + (("етапи.частина_дня",) if частина != НЕВІДОМО else ()))
    for норма in СХЕМА["норми_події"]:
        if знач("подія") == норма["подія"]:
            в["чужий_колір"] = Факт(норма["чужий_колір"], "норма_події", з_чого=("подія",))
    if знач("смуга_погоди") != НЕВІДОМО and знач("опади") != НЕВІДОМО:
        if сіль_на_дорозі(None, знач("смуга_погоди"), знач("опади"))[0]:
            в["сіль"] = Факт(True, "код", з_чого=("смуга_погоди", "опади"))
    return в


def скласти(версія, сказала, дата, *, палітра_дня=None):
    """Нова версія `Ситуації`: її поля як є, `виведено` — наново з них (виведене не пережовує старого виводу)."""
    виведено = _виведено(сказала, дата)
    if палітра_дня is not None:
        виведено["палітра_дня"] = палітра_дня
    return Ситуація(версія, {п: в for п, в in сказала.items() if п in ПОЛЯ_СКАЗАЛА}, виведено)


def порожня(дата):
    """Перша версія до її першого слова: усе «невідомо», пора року — з дати."""
    return скласти(1, {}, дата)


