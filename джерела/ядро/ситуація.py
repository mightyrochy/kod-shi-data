_МІСЦЕ_ЗВЕДЕННЯ = "x " * 400  # місце під зведення (до 200 слів) у мірі вікна, доки його не написала модель


def _від_вікна(ситуація, репліки, модель):
    """Найстарша репліка, з якої розмова разом зі зведенням влазить у вікно; не влазить і остання — `None`."""
    from . import запит

    for від in range(1, len(репліки)):
        з = запит.запит_розмови(ситуація, репліки, модель=модель, зведення=_МІСЦЕ_ЗВЕДЕННЯ, від=від)
        if not isinstance(з, Збій):
            return від
    return None


def хід(вхід):
    """Хід розмови генератором протоколу: запит розмови (Ч4) → відповідь → нова версія `Ситуації` чи `Збій`.

    Вхід: `репліки` (уся розмова: `{хто: вона|стилістка, текст}`), `ситуація` (попередня версія, JSON) чи нічого,
    `дата`, `модель`. Повертає `(Ситуація, None)` або `(попередня Ситуація без змін, Збій)` для чату."""
    from . import запит

    дата = вхід.get("дата")
    попередня = з_json(вхід["ситуація"]) if вхід.get("ситуація") else порожня(дата)
    репліки = list(вхід.get("репліки") or ())
    модель = вхід.get("модель")
    вікно = {}
    перший = запит.запит_розмови(попередня, репліки, модель=модель)
    if isinstance(перший, Збій) and перший.вид in _ПОНАД_МЕЖУ:
        # вікно + зведення (ПРОДУКТ, «Розмова»): старші репліки зводить мовна модель; код не обрізає мовчки
        від = _від_вікна(попередня, репліки, модель)
        if від is None:
            return попередня, перший
        з = запит.запит_зведення(попередня, репліки[:від], модель=модель)
        if isinstance(з, Збій):
            return попередня, з
        відп = yield з
        if "збій" in (відп or {}) or not isinstance((відп or {}).get("текст"), str) or not відп["текст"]:
            return попередня, Збій("зведення", "ситуація", None, "summary did not come", спроба=1)
        вікно = {"зведення": відп["текст"], "від": від}
    збій = None
    for спроба in range(1, СПРОБ + 1):
        з = запит.запит_розмови(попередня, репліки, модель=модель, спроба=спроба, збій=збій, **вікно)
        if isinstance(з, Збій):
            return попередня, з
        відп = yield з
        if "збій" in (відп or {}):
            сирий = відп["збій"]
            збій = Збій(сирий.get("вид") or "обрив", "ситуація", None, сирий.get("що") or "",
                        спроба=спроба, секунди=сирий.get("секунди"))
            continue
        try:
            нове = розібрати((відп or {}).get("текст"), репліки)
        except _НеЗаСхемою as п:
            збій = Збій(п.вид, "ситуація", п.поле, п.що, сирий=str((відп or {}).get("текст"))[:2000], спроба=спроба)
            continue
        except ХибнеЗначення as п:
            збій = Збій("схема", "ситуація", None, str(п), сирий=str((відп or {}).get("текст"))[:2000], спроба=спроба)
            continue
        сказала = _злити(попередня.сказала, нове)
        return скласти(попередня.версія + 1, сказала, дата, палітра_дня=попередня.виведено["палітра_дня"]), None
    return попередня, збій
