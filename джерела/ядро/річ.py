"""Ч2. Читає готовий запис каталогу й зберігає походження фактів."""
import json
import math
from pathlib import Path

from . import мітки as _мітки
from .поняття import Збій, НЕВІДОМО, НЕ_ПЕВНИЙ, Річ, Факт

with Path(__file__).with_name("дані").joinpath("поля_речі.json").open(encoding="utf-8") as _файл:
    _ПОЛЯ = json.load(_файл)

_ДЖЕРЕЛА = {
    "фото": "фото", "маска": "фото", "модель": "модель_каталогу", "модель_каталогу": "модель_каталогу",
    "крамниця": "крамниця", "слово": "крамниця", "param": "крамниця", "shop_word": "крамниця", "слово назви": "крамниця",
}
_ПУСТЕ = (None, "", НЕВІДОМО, "unknown", "?")
_ЧИСЛА = {"каблук", "блиск", "ошатність"}


def _число(значення):
    """Перевіряє скінченне число без перетворення довільного тексту."""
    if isinstance(значення, bool) or not isinstance(значення, (int, float, str)):
        raise ValueError("очікувано число")
    число = float(значення)
    if not math.isfinite(число):
        raise ValueError("очікувано скінченне число")
    return число


def _поле(запис, поле, читачі):
    """Читає одне поле в заданому порядку джерел."""
    for ключ, ключ_джерела, запас in читачі:
        значення = запис.get(ключ)
        if значення in _ПУСТЕ:
            continue
        try:
            if поле in _ЧИСЛА:
                значення = _число(значення)
            elif поле == "сезон_тканини":
                from verify import смуга_тканини, ТКАНИНА_НЕ_ПРОЧИТАНО
                значення = смуга_тканини(запис)
                if значення == ТКАНИНА_НЕ_ПРОЧИТАНО:
                    raise ValueError("невідома смуга тканини")
            elif not isinstance(значення, (str, list, tuple, dict)):
                raise ValueError("очікувано закодоване значення")
            свідчення = запис.get(ключ_джерела) if ключ_джерела is not None else None
            if ключ_джерела in ("сезон_за_чим", "тканина_за_чим") and isinstance(свідчення, (list, tuple)):
                if not свідчення or any(not isinstance(рядок, str) or not рядок for рядок in свідчення):
                    return Факт(), _заява(ключ_джерела, свідчення, "очікувано непорожній перелік свідчень")
                джерело = "крамниця" if ключ_джерела == "тканина_за_чим" else "код"
                return Факт(значення, джерело, з_чого=свідчення), None
            джерело = _ДЖЕРЕЛА.get(свідчення, запас)
            if поле == "довжина" and свідчення == "вимір: довжина виробу проти зросту":
                return Факт(значення, "код", з_чого=("довжина_джерело",),
                            межі=свідчення), None
            if поле == "рукав" and джерело != "фото":
                return Факт(НЕ_ПЕВНИЙ, джерело, межі=значення), None
            if поле == "метал":
                return Факт(НЕ_ПЕВНИЙ, джерело, межі=значення), None
            return Факт(значення, джерело), None
        except (ValueError, TypeError) as помилка:
            return Факт(), _заява(ключ, значення, помилка)
    return Факт(), None


def _заява(ключ, значення, помилка):
    """Повертає діагноз битого поля запису."""
    return Збій(вид="bad_record", частина="річ", поле=ключ, що=str(помилка), сирий=repr(значення))


def _точка(запис, вимір, слово):
    """Збирає всі колонки кольору з однієї точки й зберігає код крамниці."""
    from колір_річ import lch, точка_кольору, hex_кольору
    from колір_тон import сім_я_кольору
    lab = tuple(_число(координата) for координата in точка_кольору(вимір))
    L, _, _ = lch(lab)
    сімʼя = сім_я_кольору(lab)[0]
    return Факт({"lab": lab, "hex": hex_кольору(вимір), "L": round(L),
                 "family": сімʼя, "color": сімʼя,
                 "слово_крамниці": слово}, "фото")


def _колір(запис):
    """Бере придатний вимір або межі слова крамниці."""
    if not any(запис.get(ключ) for ключ in ("колір_вимір", "колір_слово", "колір_тип", "колір_ім")):
        return Факт()
    from колір_річ import точка_кольору, вікно_кольору
    вимір = запис.get("колір_вимір") or запис
    слово = запис.get("колір_назва_сира") or запис.get("колір_назва")
    джерело = запис.get("колір_джерело", запис.get("джерело_кольору"))
    if вимір.get("придатний") is True or (вимір is запис and джерело == "фото" and точка_кольору(вимір)):
        return _точка(запис, вимір, слово)
    межі = вікно_кольору(запис.get("колір_слово") or запис)
    if межі:
        return Факт(НЕ_ПЕВНИЙ, "крамниця",
                    межі={"вікно": межі, "color": запис.get("колір_ім"), "слово_крамниці": слово})
    if вимір is not запис and точка_кольору(вимір):
        return Факт(НЕ_ПЕВНИЙ, "фото", межі={"lab": точка_кольору(вимір),
                                            "чому": вимір.get("чому"), "слово_крамниці": слово})
    код = запис.get("колір_ім")
    return Факт({"color": код, "слово_крамниці": слово}, "крамниця") if код else Факт()


def _довжина_виробу(запис):
    """Зберігає вимір виробу зі штатною точкою та розкидом, коли він є."""
    см, точка = запис.get("довжина_виробу_см"), запис.get("довжина_виробу_точка")
    if см is None or not точка:
        return Факт()
    факти = {"довжина_виробу_см": _число(см), "довжина_виробу_точка": точка}
    if запис.get("довжина_виробу_розкид_см") is not None:
        факти["довжина_виробу_розкид_см"] = _число(запис["довжина_виробу_розкид_см"])
    for ключ in ("довжина_виробу_за_чим", "край_джерело"):
        if запис.get(ключ) is not None:
            факти[ключ] = запис[ключ]
    return Факт(факти, "крамниця", з_чого=tuple(факти))


def _комір(запис):
    """Читає ознаку зі слів крамниці у двох штатних форматах."""
    шлях = ("ознаки_зі_слів", "верхні", "комір") if запис.get("ознаки_зі_слів") is not None else ("комір",)
    значення = запис
    for рівень, ключ in enumerate(шлях[:-1], 1):
        значення = значення.get(ключ)
        if значення is None:
            return Факт(), None
        if not isinstance(значення, dict):
            return Факт(), _заява(".".join(шлях[:рівень]), значення, "очікувано об’єкт")
    значення = значення.get(шлях[-1])
    if значення in _ПУСТЕ:
        return Факт(), None
    if not isinstance(значення, str):
        return Факт(), _заява(".".join(шлях), значення, "очікувано код коміра")
    return Факт(значення, "крамниця", з_чого=шлях), None


def _підошва(запис):
    """Читає коди картки й стару основу слова одним визначенням підошви."""
    from пара_взуття import підошва

    for ключ, тип in (("підошва_коди", (list, tuple)), ("підошва", str)):
        сире = запис.get(ключ)
        if сире in _ПУСТЕ:
            continue
        if not isinstance(сире, тип) or (ключ == "підошва_коди" and any(
                not isinstance(код, str) or not код for код in сире)):
            return Факт(), _заява(ключ, сире, "очікувано коди підошви або основу слова крамниці")
    чистий = {к: запис[к] for к in ("підошва_коди", "підошва") if запис.get(к) not in _ПУСТЕ}
    if not чистий:
        return Факт(), None
    коди, _ = підошва(чистий)
    if not коди:
        return Факт(), None
    джерела = tuple(ключ for ключ in ("підошва_коди", "підошва") if чистий.get(ключ))
    свідчення = запис.get("підошва_джерело") if not чистий.get("підошва_коди") else None
    if свідчення is not None and not isinstance(свідчення, str):
        return Факт(), _заява("підошва_джерело", свідчення, "очікувано код джерела")
    джерело = _ДЖЕРЕЛА.get(свідчення, "крамниця")
    return Факт(tuple(коди), джерело, з_чого=джерела), None


def _новий_запис(новий, слот, поля, збої):
    """Запис речі нового виду (`мітки.py`): відома мітка стає полем зі своїм джерелом; «невідомо» лишає поле
    старому читачеві рядка каталогу, а мітку поза слотом чи з битим значенням — ні, із заявою."""
    if not isinstance(новий, dict) or not isinstance(новий.get("мітки", {}), dict):
        збої.append(_заява("мітки_речі", новий, "очікувано об’єкт {опис, мітки}"))
        return НЕВІДОМО
    мітки = новий.get("мітки", {})
    for поле, сире in мітки.items():
        if поле in ("слот", "колір") or поле in _мітки.ВИВЕДЕНІ:
            continue
        факт = _мітки.факт_мітки(поле, сире, слот) if поле in _мітки.ЗАПИТАНІ else None
        if факт is None:
            if сире is not None and (поле not in _мітки.ЗАПИТАНІ or _мітки.застосовна(поле, слот)):
                збої.append(_заява(f"мітки_речі.{поле}", сире, "мітка поза визначенням чи кодами"))
            continue
        поля[поле] = факт
    опис = новий.get("опис")
    return опис if isinstance(опис, str) and опис else НЕВІДОМО


def _колір_запису(новий, запис, збої):
    """Колір речі, коли є запис нового виду: коди відтінку чи «не певний» від моделі зору з галереї (`відтінки.py`).
    Відповіді моделі нема (чи вона бита — із заявою) — лише інтервал слова крамниці (вікно коду кольору), а без вікна —
    «невідомо»: ні піксельного виміру, ні коду слова як відомого кольору тут нема (корінь `Річ-колір-вимір`,
    «Інваріант ПІСЛЯ»). Рядок каталогу без запису нового виду читає `_колір`, як і досі."""
    from . import відтінки as _відтінки
    from колір_річ import вікно_кольору

    мітки = новий.get("мітки") if isinstance(новий, dict) else None
    сире = мітки.get("колір") if isinstance(мітки, dict) else None
    слово = запис.get("колір_назва_сира") or запис.get("колір_назва")
    if сире is not None:
        перевірене, збій = (_мітки.мітка("колір", {"в": сире.get("значення"), "дж": сире.get("джерело"),
                                                   "межі": сире.get("межі"), "принт": сире.get("принт")})
                            if isinstance(сире, dict) else (None, "очікувано об’єкт {значення, джерело}"))
        if збій:
            збої.append(_заява("мітки_речі.колір", сире, збій))
        elif перевірене is not None:
            return _відтінки.факт(перевірене, слово)
    межі = вікно_кольору(запис.get("колір_слово") or запис)
    if межі:
        return Факт(НЕ_ПЕВНИЙ, "крамниця",
                    межі={"вікно": межі, "color": запис.get("колір_ім"), "слово_крамниці": слово})
    return Факт()


def читати(запис):
    """Повертає Річ. Бите поле дає невідоме значення й діагноз."""
    поля, збої = {}, []
    for поле, читачі in _ПОЛЯ.items():
        поля[поле], збій = _поле(запис, поле, читачі)
        if збій:
            збої.append(збій)
    поля["підошва"], збій = _підошва(запис)
    if збій:
        збої.append(збій)
    try:
        поля["колір"] = _колір(запис)
    except (ValueError, TypeError, KeyError, IndexError, AttributeError) as помилка:
        поля["колір"] = Факт()
        збої.append(_заява("колір", запис.get("колір_вимір"), помилка))
    if поля["ошатність"].значення == НЕВІДОМО and поля["тип"].значення != НЕВІДОМО \
            and not any(з.поле == "формальність" for з in збої):
        try:
            from формальність import інтервал_формальності
            низ, верх = інтервал_формальності({"тип": поля["тип"].значення,
                                               "тип_модифікатор": запис.get("тип_модифікатор")})
            if низ is not None:
                поля["ошатність"] = Факт((низ, верх), "код", з_чого=("тип", "тип_модифікатор"))
        except (ValueError, TypeError) as помилка:
            збої.append(_заява("формальність", запис.get("формальність"), помилка))
    try:
        поля["довжина_виробу"] = _довжина_виробу(запис)
    except (ValueError, TypeError) as помилка:
        збої.append(_заява("довжина_виробу", запис.get("довжина_виробу_см"), помилка))
    поля["комір"], збій = _комір(запис)
    if збій:
        збої.append(збій)
    слот, опис = запис.get("слот") or НЕВІДОМО, НЕВІДОМО
    новий = запис.get("мітки_речі")
    if новий is not None:
        опис = _новий_запис(новий, слот, поля, збої)
        try:
            поля["колір"] = _колір_запису(новий, запис, збої)
        except (ValueError, TypeError, KeyError, IndexError, AttributeError) as помилка:
            поля["колір"] = Факт()
            збої.append(_заява("мітки_речі.колір", новий, помилка))
    поля["тепло_шару"] = _мітки.тепло_шару(слот, поля["тканина"], поля.get("утеплення", Факт()))
    фото = запис.get("фото") or ()
    if isinstance(фото, str):
        фото = (фото,)
    return Річ(ід=запис["id"], слот=слот, опис=опис,
               назва=запис.get("назва_показу") or запис.get("назва") or НЕВІДОМО,
               крамниця=запис.get("магазин") or НЕВІДОМО, ціна=запис.get("ціна", НЕВІДОМО),
               фото=tuple(ф for ф in фото if isinstance(ф, str) and ф), url=запис.get("url") or НЕВІДОМО,
               поля=поля, збої=tuple(збої), джерело_слота=запис.get("джерело_слота"))
