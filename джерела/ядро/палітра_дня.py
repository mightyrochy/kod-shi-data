"""Портрет і план палітри дня для пулу, запиту й суду ядра."""
from collections import Counter

from .поняття import НЕВІДОМО


def _поля_моделі(гілка, вибір, день):
    from автор_палітри import автор_палітри, ОСНОВА_З_РЕЧІ
    from внутрішня_мова import код, код_або_невідомо
    from палітра_для_моделі import рядки_кольорів_слотів
    from траурний_регістр import траур_сцени

    поля = {}
    автор = автор_палітри(вибір, "base")
    колір = вибір.get("база_назва")
    основа = " ".join(в for в in (код("color_name", колір) or колір, вибір.get("база_hex")) if в)
    if автор and основа:
        поля["base"] = {"colour": основа, "chosen_by": "her" if автор == ОСНОВА_З_РЕЧІ else автор}
    спец = (гілка or {}).get("спец") or {}
    слоти = спец.get("слоти") or {}
    if not слоти:
        return поля
    поля["slot_roles"] = {код_або_невідомо("slot", слот): код_або_невідомо("scheme_role", дані["роль"])
                          for слот, дані in слоти.items() if дані.get("роль")}
    _, _, види = рядки_кольорів_слотів(гілка, вибір=вибір)
    if види:
        поля["kind_colours"] = {вид: {ключ: в for ключ, в in дані.items() if (ключ, в) != ("hue", "fixed")}
                                for вид, дані in види.items()}
    великі = спец.get("поверхні") == "великі" and спец.get("сім_ї_схеми")
    траур = траур_сцени(день)
    if not великі and not (траур and траур.get("лишилось")):
        акценти = [код_або_невідомо("slot", слот) for слот, дані in слоти.items()
                   if дані.get("роль") == "акцент" and дані.get("C") and float(дані["C"][0]) > 0]
        if акценти:
            поля["colour_kinds"] = акценти[:6]
    return поля


def портрет_і_палітра(вхід, ситуація):
    """Бере риси з профілю і рахує вікна лише з відомих входів; та сама специфікація йде до суду."""
    from colorspace import додати_макіяж
    from face_features import джерело_виміру
    from внутрішня_мова import ТАБЛИЦЯ
    from палітра_специфікація import розвилка_специфікацій, специфікація
    from палітра_запити import запит_у_фід
    from вікна_аксесуарів import розкрити_аксесуари
    from портрет_вхід import features, нормувати_елісітацію, вимір_портрета
    from реєстр_намір import ТИПОВИЙ_НАМІР
    from смуга_кольору_основи import смуга_L_основи
    from .знання import день_правил
    from .пул import СЛОТИ

    профіль = вхід.get("профіль") or {}
    колір = профіль.get("колір") or {}
    палітра = профіль.get("палітра") or {}
    вибір = палітра.get("вибір_кольору") or {}
    макіяж = (профіль.get("сценарій") or {}).get("макіяж")
    д = {**колір, "очі_кільце": колір.get("кільце"), "портрет_вимір": колір.get("вимір")}
    нема = (None, "", НЕВІДОМО, "unknown")
    for ключ in ("шкіра", "волосся", "очі", "очі_кільце"):
        значення = д.get(ключ)
        if isinstance(значення, (list, tuple)):
            д[ключ] = [к for к in значення if к not in нема]
        elif значення in нема:
            д[ключ] = None
    вимір = вимір_портрета(д)
    повний = вимір is not None or all(д[к] for к in ("шкіра", "волосся", "очі"))
    є_риси = bool(вимір or any(д[к] for к in ("шкіра", "волосся", "очі", "очі_кільце")) or макіяж)
    риси = додати_макіяж(features(д, неповний_портрет=not повний)[0], макіяж)[0] if є_риси else {}
    день = день_правил(ситуація)
    if not повний:
        поля = _поля_моделі(None, вибір, день)
        return риси, {"дані": {}, "поля_дроту": поля, "вікна": ()} if поля else None

    обрана = ситуація.сказала["схема"]
    має_її_вибір = обрана.значення not in нема
    схема = обрана.значення if має_її_вибір else палітра.get("схема")
    схема = ТАБЛИЦЯ["palette_scheme"].get(схема, схема)
    елісітація = нормувати_елісітацію(профіль.get("драп"))
    основа = вибір.get("база_hex") if вибір.get("база_тип") == "колір" else None
    намір = день.get("intent") or ТИПОВИЙ_НАМІР
    параметри = {"source": джерело_виміру(риси), "intent": намір, "якір_тон": основа,
                 "самозвіт": елісітація["самозвіт"], "драп": елісітація["драп"],
                 "насиченість": вибір.get("насиченість")}
    розвилка = розвилка_специфікацій(риси, СЛОТИ, **параметри, явні=(схема,) if схема else ())
    гілки = [г for г in розвилка["розвилка"] if г.get("спец")]
    обрана_гілка = next((г for г in гілки if г["схема"] == схема), None)
    if схема is None and палітра.get("гілка") is not None:
        індекс = int(палітра["гілка"])
        if 0 <= індекс < len(розвилка["розвилка"]):
            г = розвилка["розвилка"][індекс]
            обрана_гілка = г if г.get("спец") else None

    def вікна(г):
        if основа:
            г["спец"] = специфікація(риси, г["схема"], СЛОТИ, **параметри,
                                       основа=dict(вибір, смуга_L=смуга_L_основи(основа)))
        запити = запит_у_фід(г["спец"])
        return tuple(в for в in розкрити_аксесуари(запити) if isinstance(в, dict) and в.get("L_min") is not None)

    гілка = обрана_гілка or next(iter(гілки), None)
    основні, межові = [], []
    for г in гілки:
        ряд = основні if г is гілка else межові
        ряд.extend(вікна(г))
    if not основні:
        поля = _поля_моделі(None, вибір, день)
        return риси, {"дані": {}, "поля_дроту": поля, "вікна": ()} if поля else None
    хвилі = Counter(в.get("спроба", 0) for в in основні)
    дані = {"scheme": гілка["схема"], "default_branch": обрана_гілка is None, "window_count": len(основні),
            "window_waves": [{"wave": хвиля, "count": n} for хвиля, n in sorted(хвилі.items())]}
    if схема and обрана_гілка is None:
        дані["unknown_scheme"] = схема
    автор = ("her" if обрана.джерело == "форма" else "conversation") if має_її_вибір else (
        "stylist" if палітра.get("схема_стилістки") else "her" if обрана_гілка else "code_rank")
    return риси, {"дані": дані, "поля_дроту": _поля_моделі(гілка, вибір, день),
                  "спец": гілка["спец"], "вікна": tuple(основні), "вікна_межі": tuple(межові),
                  "пакет": {"палітри": розвилка}, **елісітація, "вибір_схеми": {"обрала": {"scheme": автор}}}
