"""Одне місце речі перед пулом і складанням образу."""
import json
from pathlib import Path

from .поняття import НЕВІДОМО

with Path(__file__).with_name("дані").joinpath("добір.json").open(encoding="utf-8") as _файл:
    ДОБІР = json.load(_файл)

СЛОТИ_КАТАЛОГУ = ДОБІР["слоти"]
_МІСЦЯ = ДОБІР["місця_запису"]
НОВІ_СЛОТИ = _МІСЦЯ["нові"]
СЛОТИ = СЛОТИ_КАТАЛОГУ | НОВІ_СЛОТИ
_ВІДПОВІДНИКИ = _МІСЦЯ["відповідники"]
СЛОТИ_ЗАПИСУ = tuple(слот for слот in СЛОТИ if слот not in _ВІДПОВІДНИКИ)
_ЗА_ТИПОМ = {тип: слот for слот, типи in _МІСЦЯ["типи"].items() for тип in типи}


def з_каталогу(слот):
    """Зводить успадковані коди місця до коду запису."""
    return _ВІДПОВІДНИКИ.get(слот, слот) if isinstance(слот, str) else слот


def із_запису(ід, слот_каталогу, мітки):
    """Вибирає один код місця й джерело з міток, застосовуючи рішення паспорта."""
    from . import мітки as визначення

    if ід in _МІСЦЯ["без_місця"]:
        return НЕВІДОМО, None
    сире = мітки.get("слот")
    if isinstance(сире, dict) and isinstance(сире.get("джерело"), str):
        слот = з_каталогу(сире.get("значення"))
        факт = визначення.факт_мітки("слот", dict(сире, значення=слот), слот_каталогу)
        if (факт and isinstance(слот_каталогу, str)
                and факт.значення in _МІСЦЯ["виняток_каталогу"].get(слот_каталогу, ())):
            return слот_каталогу, "каталог"
    else:
        факт = None
    сирий_тип = мітки.get("тип")
    if isinstance(сирий_тип, dict):
        тип = сирий_тип.get("значення")
        джерело = сирий_тип.get("джерело")
        if isinstance(тип, str) and тип in _ЗА_ТИПОМ and джерело in визначення.МІТКИ["тип"]["джерела"]:
            виправлене = _ЗА_ТИПОМ[тип]
            return виправлене, факт.джерело if факт and факт.значення == виправлене else джерело
    if факт and факт.значення in СЛОТИ_ЗАПИСУ:
        return факт.значення, факт.джерело
    return НЕВІДОМО, None
