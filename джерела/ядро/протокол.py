"""Протокол «ядро просить — показ везе» (`ОПИС.md`, розділ 5): вхід мосту `ядро` у `bridge.виклик`.

Показ шле `{"дія": "почати", "вхід": …}`, ядро відповідає запитами до моделі; кожну відповідь моделі показ везе назад
`{"дія": "відповідь", "сесія", "ключ", "відповідь": {"текст"} | {"збій": {вид, секунди, що}}}` тією самою функцією
моделі, чергою, повторами й журналом, що й тепер (збій — модуль `збій_моделі.js`, #4512). Руки — генератори в
словнику сесій. Картки ядро віддає всі разом, коли скінчили всі руки (рішення власника 27.09; дошка 16957), на
позиціях, що не видають руки. Рука зупиняється лише зі `Збій` на своїй картці (Т33); інші руки йдуть далі. Сесія
старішої версії `Ситуації`, ніж остання почата в цій розмові, карток не віддає — лише заяву в звіт (Т35).

Розмова теж іде ядром (Н4): `{"дія": "розмова", "вхід": {розмова, репліки, ситуація, дата, модель}}` — Ч1 просить
запит розмови (Ч4 будує), показ везе відповідь, ядро віддає нову версію `Ситуації` чи `Збій` для чату; `{"дія": "тап",
"вхід": {ситуація, поле, значення, дата}}` — тап плитки пише ту саму `Ситуацію` з джерелом `форма`. `Ситуацію` між
викликами тримає показ: у ядрі стану розмови нема, а сесії, яких ніхто не довів до кінця, витісняє нова сесія тієї
самої розмови чи межа `СЕСІЙ` (Т47: той самий вхід — той самий вихід і в свіжому процесі).
"""
import json
import os
import random

from . import картка as картка_м, запит, пул, розбір, руки, ситуація, суд, знання
from .поняття import Збій, Запит, Картка, ХибнеЗначення

РУКИ = (1, 2, 3, 4)
ВХІД = frozenset({"розмова", "сід", "дата", "ситуація", "профіль", "перемикачі", "каталог", "модель", "її_речі"})
ВХІД_РОЗМОВИ = frozenset({"розмова", "репліки", "ситуація", "дата", "модель"})
ВХІД_ТАПУ = frozenset({"розмова", "ситуація", "поле", "значення", "дата", "репліки"})
ВХІД_ПАЛІТРИ = frozenset({"вибір", "ситуація", "дата", "модель"})
СЕСІЙ = 16  # незавершених сесій у пам'яті процесу: старіші витісняються, а не лишаються назавжди
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "дані", "перемикачі.json"), encoding="utf-8") as _ф:
    ПЕРЕМИКАЧІ = json.load(_ф)["перемикачі"]

_СЕСІЇ = {}
_ОСТАННЯ = {}
_ЛІЧИЛЬНИК = [0]


def виклик(вхід):
    """Вхід мосту: JSON-рядок (чи словник) дії → JSON-рядок відповіді ядра."""
    д = json.loads(вхід) if isinstance(вхід, str) else вхід
    if д.get("дія") == "почати":
        в = почати(д.get("вхід") or {})
    elif д.get("дія") == "відповідь":
        в = відповідь(д.get("сесія"), д.get("ключ"), д.get("відповідь") or {})
    elif д.get("дія") == "розмова":
        в = розмова(д.get("вхід") or {})
    elif д.get("дія") == "тап":
        в = тап(д.get("вхід") or {})
    elif д.get("дія") == "палітра":
        в = палітра(д.get("вхід") or {})
    else:
        в = _кінець(None, Збій(вид="дія", частина="протокол", поле="дія", що=repr(д.get("дія"))))
    return json.dumps(в, ensure_ascii=False)


def _кінець(сесія, збій, звіт=()):
    return {"сесія": сесія, "запити": [], "картки": [], "кінець": True, "збій": збій.в_json(), "звіт": list(звіт)}


def _перемикачі(дані):
    пм = {к: опис["типове"] for к, опис in ПЕРЕМИКАЧІ.items() if not опис.get("лише_названий")}
    for к, в in (дані or {}).items():
        if к not in ПЕРЕМИКАЧІ or в not in ПЕРЕМИКАЧІ[к]["значення"]:
            return Збій(вид="перемикач", частина="протокол", поле=к, що=repr(в))
        пм[к] = в
    return пм


def _каталог(вхід):
    """Читає ту саму таблицю каталогу, що її вкладає збірка."""
    шлях = вхід.get("каталог")
    if isinstance(шлях, list):
        return шлях
    if not шлях:
        return ()
    from фід_каталог import база_прогону
    return база_прогону(шлях, ліміт_фото=0, кеш="кеш.json")["каталог"]


def _нова_сесія(стан):
    """Нова сесія витісняє незавершені сесії розмови тієї самої дії й найстаріші понад межу `СЕСІЙ`."""
    for ключ in [к for к, с in _СЕСІЇ.items() if с["розмова"] == стан["розмова"] and с.get("дія") == "розмова"
                 and стан.get("дія") == "розмова"]:
        del _СЕСІЇ[ключ]
    while len(_СЕСІЇ) >= СЕСІЙ:
        del _СЕСІЇ[next(iter(_СЕСІЇ))]
    _ЛІЧИЛЬНИК[0] += 1
    сесія = f"я-{_ЛІЧИЛЬНИК[0]}"
    _СЕСІЇ[сесія] = стан
    return сесія


def розмова(вхід):
    """Хід розмови: Ч1 просить запит розмови, відповідь дає нову версію `Ситуації` чи `Збій` для чату."""
    чужі = sorted(set(вхід) - ВХІД_РОЗМОВИ)
    if чужі:
        return _кінець(None, Збій(вид="схема", частина="протокол", поле=чужі[0], що="чужий ключ входу"))
    стан = {"дія": "розмова", "розмова": вхід.get("розмова") or "без_розмови", "генератор": ситуація.хід(вхід),
            "чекає": None, "репліки": list(вхід.get("репліки") or ())}
    сесія = _нова_сесія(стан)
    return _крок_розмови(сесія, None)


def палітра(вхід):
    """Палітра дня окремим викликом (п.5): запит стилістки будує Ч4, відповідь читає старий виробник палітри; кінець
    несе його вибір (`палітра`) — показ кладе його в профіль, і `почати` пише `виведено.палітра_дня` з джерелом
    `стилістка`. Ситуація тут не міняється."""
    чужі = sorted(set(вхід) - ВХІД_ПАЛІТРИ)
    if чужі:
        return _кінець(None, Збій(вид="схема", частина="протокол", поле=чужі[0], що="чужий ключ входу"))
    стан = {"дія": "палітра", "розмова": "палітра", "генератор": _хід_палітри(вхід), "чекає": None, "репліки": []}
    return _крок_розмови(_нова_сесія(стан), None)


def _хід_палітри(вхід):
    попередня = (ситуація.з_json(вхід["ситуація"]) if вхід.get("ситуація")
                 else ситуація.порожня(вхід.get("дата")))
    вибір = dict(вхід.get("вибір") or {})
    р = знання.вибір_палітри(вибір)
    if р.get("помилка"):
        return попередня, Збій(вид="палітра", частина="знання", поле="вибір", що=str(р["помилка"])), None
    if р.get("нічого") or not р.get("промпт"):
        return попередня, None, р
    промпт, перший = р["промпт"], р["промпт"]
    for спроба in (1, 2):
        з = запит.запит_палітри(промпт, попередня, модель=вхід.get("модель"), спроба=спроба)
        if isinstance(з, Збій):
            return попередня, з, знання.вибір_палітри(dict(вибір, без_моделі=f"{з.вид}: {з.що}"))
        відп = yield з
        текст = (відп or {}).get("текст")
        if "збій" in (відп or {}) or not isinstance(текст, str) or not текст:
            причина = ((відп or {}).get("збій") or {}).get("вид") or "no_text"
            return попередня, None, знання.вибір_палітри(dict(вибір, без_моделі=f"model_no_answer: {причина}"))
        # перший крок 2 несе промпт (повтор можливий), повтору — без нього: не прочиталась і тепер — ранг коду
        р = знання.вибір_палітри(dict(вибір, відповідь_моделі=текст, **({"промпт": перший} if спроба == 1 else {})))
        if спроба == 1 and р.get("промпт_повтору"):
            промпт = р["промпт_повтору"]
            continue
        return попередня, None, р
    return попередня, None, р


def _крок_розмови(сесія, відп):
    стан = _СЕСІЇ[сесія]
    try:
        з = next(стан["генератор"]) if відп is None else стан["генератор"].send(відп)
    except StopIteration as кінець:
        del _СЕСІЇ[сесія]
        if стан["дія"] == "палітра":
            с, збій, вибір = кінець.value
            return {"сесія": сесія, "запити": [], "картки": [], "кінець": True, "ситуація": с.в_json(),
                    "палітра": вибір, "збій": збій.в_json() if збій else None, "звіт": []}
        с, збій = кінець.value
        if not збій:
            _оновити_версію(стан["розмова"], с.версія)
        return {"сесія": сесія, "запити": [], "картки": [], "кінець": True, "ситуація": с.в_json(),
                "картка_сценарію": ситуація.картка_сценарію(с, стан["репліки"]),
                "збій": збій.в_json() if збій else None, "звіт": []}
    except (ValueError, KeyError, TypeError) as помилка:
        del _СЕСІЇ[сесія]
        return _кінець(сесія, Збій(вид="вхід", частина="ситуація", що=f"{type(помилка).__name__}: {помилка}"))
    стан["чекає"] = з.ключ
    return {"сесія": сесія, "запити": [dict(з.в_json(), сесія=сесія)], "картки": [], "кінець": False, "звіт": []}


def тап(вхід):
    """Тап плитки: та сама `Ситуація`, нова версія, джерело `форма` (Т8)."""
    чужі = sorted(set(вхід) - ВХІД_ТАПУ)
    if чужі:
        return _кінець(None, Збій(вид="схема", частина="протокол", поле=чужі[0], що="чужий ключ входу"))
    try:
        попередня = (ситуація.з_json(вхід["ситуація"]) if вхід.get("ситуація")
                     else ситуація.порожня(вхід.get("дата")))
        с = ситуація.тап(попередня, вхід.get("поле"), знання.значення_тапу(вхід.get("поле"), вхід.get("значення")),
                         вхід.get("дата"))
    except (ХибнеЗначення, KeyError, TypeError) as помилка:
        return _кінець(None, Збій(вид="тап", частина="ситуація", поле=вхід.get("поле"),
                                  що=f"{type(помилка).__name__}: {помилка}"))
    if вхід.get("розмова"):
        _оновити_версію(вхід["розмова"], с.версія)
    return {"сесія": None, "запити": [], "картки": [], "кінець": True, "ситуація": с.в_json(),
            "картка_сценарію": ситуація.картка_сценарію(с, вхід.get("репліки")), "збій": None, "звіт": []}


def _оновити_версію(розмова, версія):
    """Запам'ятовує версію, яку вже одержав показ."""
    _ОСТАННЯ[розмова] = max(_ОСТАННЯ.get(розмова, 0), версія)
    while len(_ОСТАННЯ) > СЕСІЙ:
        del _ОСТАННЯ[next(iter(_ОСТАННЯ))]


def почати(вхід):
    чужі = sorted(set(вхід) - ВХІД)
    if чужі:
        return _кінець(None, Збій(вид="схема", частина="протокол", поле=чужі[0], що="чужий ключ входу"))
    пм = _перемикачі(вхід.get("перемикачі"))
    if isinstance(пм, Збій):
        return _кінець(None, пм)
    try:
        каталог = _каталог(вхід)
        if пм.get("записи_речі") == "нові":
            from .записи_речей import вкласти
            каталог = вкласти(каталог)
        с = (ситуація.з_json(вхід["ситуація"]) if вхід.get("ситуація")
             else ситуація.порожня(вхід.get("дата")))
        риси, план_палітри = знання.портрет_і_палітра(вхід, с) if каталог else ({}, None)
        с = ситуація.з_профілем(с, план_палітри, риси, знання.хто_обрав_палітру(вхід))
        профіль = знання.профіль_суду(вхід.get("профіль") or {})
        її_речі = знання.її_речі(вхід.get("її_речі"))
    except (ValueError, OSError, KeyError, TypeError) as помилка:
        return _кінець(None, Збій(вид="вхід", частина="протокол", що=f"{type(помилка).__name__}: {помилка}"))
    розмова = вхід.get("розмова") or "без_розмови"
    _оновити_версію(розмова, с.версія)
    сід = int(вхід.get("сід") or 0)
    стан = {"дія": "почати", "розмова": розмова, "версія": с.версія, "сід": сід, "перемикачі": пм, "руки": {},
            "чекає": {}, "групи": {}, "картки": {}, "звіт": []}
    сесія = _нова_сесія(стан)
    запити = []
    # Жереб руки 2 — зі знань на сирому сіді прогону; поломки — значення на вході її частин.
    поломки = знання.жереб_поломок(с, сід, профіль) if каталог else None
    for р in РУКИ:
        стан["руки"][р] = руки.рука(р, с, сід + р - 1, пм, каталог,
                                      профіль, вхід.get("модель"), стан["звіт"],
                                      **({"поломки": поломки} if р == 2 else {}),
                                      **({"профіль_сирий": вхід.get("профіль") or {}, "її_речі": її_речі}
                                         if р in (3, 4) else {}))
        запити += _крок(сесія, р, None)
    return _відповідь(сесія, запити)


def _крок(сесія, рука, відп):
    """Один крок генератора руки: новий запит або картка руки (виняток — `Збій` на картці, не тиша)."""
    стан = _СЕСІЇ[сесія]
    генератор = стан["руки"][рука]
    try:
        вихід = next(генератор) if відп is None else генератор.send(відп)
    except StopIteration as кінець:
        результат = кінець.value
        стан["картки"][рука] = (картка_м.зі_збою(рука, стан["версія"], Збій("немає_пояснення", "картка"))
                                  if not результат.збій and not isinstance(результат, Картка) else результат)
        return []
    except Exception as п:
        стан["картки"][рука] = картка_м.зі_збою(рука, стан["версія"], Збій(
            вид="виняток", частина="руки", що=f"{type(п).__name__}: {п}"))
        return []
    # Кортеж запитів — одночасні запити однієї руки (частини пулу): показ везе їх паралельно, рука отримує словник
    # відповідей за ключем, коли прийшли всі (`відповідь`).
    група = вихід if isinstance(вихід, tuple) else (вихід,)
    if not група or not all(isinstance(з, Запит) for з in група):
        стан["картки"][рука] = картка_м.зі_збою(рука, стан["версія"], Збій(
            вид="протокол", частина="руки", що=f"рука віддала {type(вихід).__name__}, а не запит"))
        return []
    for з in група:
        стан["чекає"][з.ключ] = рука
    if isinstance(вихід, tuple):
        стан["групи"][рука] = {"ключі": {з.ключ for з in група}, "відповіді": {}}
    return [dict(з.в_json(), сесія=сесія, перемикачі=стан["перемикачі"]) for з in група]


def відповідь(сесія, ключ, відп):
    стан = _СЕСІЇ.get(сесія)
    if стан is None:
        return _кінець(сесія, Збій(вид="сесія", частина="протокол", поле="сесія", що=repr(сесія)))
    if стан.get("дія") in ("розмова", "палітра"):
        if ключ != стан["чекає"]:
            return _кінець(сесія, Збій(вид="ключ", частина="протокол", поле="ключ", що=repr(ключ)))
        return _крок_розмови(сесія, відп)
    рука = стан["чекає"].pop(ключ, None)
    if рука is None:
        return _кінець(сесія, Збій(вид="ключ", частина="протокол", поле="ключ", що=repr(ключ)))
    поточна = _ОСТАННЯ.get(стан["розмова"], стан["версія"])
    if стан["версія"] < поточна:
        стан["картки"][рука] = картка_м.зі_збою(рука, стан["версія"],
            Збій("застаріла_версія", "протокол", "версія_ситуації"))
        return _відповідь(сесія, [])
    група = стан["групи"].get(рука)
    if група is not None:
        група["відповіді"][ключ] = відп
        if len(група["відповіді"]) < len(група["ключі"]):
            return _відповідь(сесія, [])
        del стан["групи"][рука]
        відп = група["відповіді"]
    return _відповідь(сесія, _крок(сесія, рука, відп))


def _відповідь(сесія, запити):
    стан = _СЕСІЇ[сесія]
    в = {"сесія": сесія, "запити": запити, "картки": [], "кінець": False, "звіт": [],
         "заглушки": {"ситуація": ситуація.НАРЯД, "пул": пул.НАРЯД, "запит": запит.НАРЯД, "розбір": розбір.НАРЯД,
                      "суд": суд.НАРЯД, "картка": картка_м.НАРЯД, "руки": руки.НАРЯД}}
    if len(стан["картки"]) < len(РУКИ):
        return в
    del _СЕСІЇ[сесія]
    в["кінець"] = True
    поточна = _ОСТАННЯ.get(стан["розмова"], стан["версія"])
    звіт = стан["звіт"] + [{"рука": р, "збій": к.збій.в_json()}
                            for р, к in sorted(стан["картки"].items()) if к.збій]
    if стан["версія"] < поточна:
        в["звіт"] = звіт + [{"заява": "застаріла_версія", "версія_ситуації": стан["версія"], "поточна": поточна}]
        return в
    if all(к.збій for к in стан["картки"].values()):
        перевищення = next((к.збій for к in стан["картки"].values()
                            if к.збій.частина == "запит" and к.збій.вид in ("вікно_моделі", "межа_транспорту")), None)
        if перевищення:
            return dict(в, збій=перевищення.в_json(), звіт=звіт)
    позиції = random.Random(стан["сід"]).sample(range(len(РУКИ)), len(РУКИ))
    в["відмови"] = []
    for рука, позиція in sorted(zip(РУКИ, позиції), key=lambda пара: пара[1]):
        результат = картка_м.на_позиції(стан["картки"][рука], позиція)
        в["відмови" if результат.збій else "картки"].append(результат.в_json())
    в["звіт"] = звіт
    return в
