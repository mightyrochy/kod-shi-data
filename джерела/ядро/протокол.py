"""Протокол «ядро просить — показ везе» (`ОПИС.md`, розділ 5): вхід мосту `ядро` у `bridge.виклик`.

Показ шле `{"дія": "почати", "вхід": …}`, ядро відповідає запитами до моделі; кожну відповідь моделі показ везе назад
`{"дія": "відповідь", "сесія", "ключ", "відповідь": {"текст"} | {"збій": {вид, секунди, що}}}` тією самою функцією
моделі, чергою, повторами й журналом, що й тепер (збій — модуль `збій_моделі.js`, #4512). Руки — генератори в
словнику сесій. Картки ядро віддає всі разом, коли скінчили всі руки (рішення власника 27.09; дошка 16957), на
позиціях, що не видають руки. Рука зупиняється лише зі `Збій` на своїй картці (Т33); інші руки йдуть далі. Сесія
старішої версії `Ситуації`, ніж остання почата в цій розмові, карток не віддає — лише заяву в звіт (Т35).
"""
import json
import os
import random

from . import картка as картка_м, запит, пул, розбір, руки, ситуація, суд, знання, перекладач_паспорта
from .поняття import Збій, Запит

РУКИ = (1, 2, 3, 4)
ВХІД = frozenset({"розмова", "версія", "сід", "дата", "паспорт", "профіль", "перемикачі", "каталог", "модель"})
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "дані", "перемикачі.json"), encoding="utf-8") as _ф:
    ПЕРЕМИКАЧІ = json.load(_ф)["перемикачі"]

_СЕСІЇ = {}
_ОСТАННЯ = {}
_ЛІЧИЛЬНИК = [0]


def виклик(вхід):
    """Вхід мосту: JSON-рядок (чи словник) дії → JSON-рядок відповіді ядра."""
    д = json.loads(вхід) if isinstance(вхід, str) else вхід
    if д.get("дія") == "почати":
        в = почати(д.get("вхід") or {})
    elif д.get("дія") == "відповідь":
        в = відповідь(д.get("сесія"), д.get("ключ"), д.get("відповідь") or {})
    else:
        в = _кінець(None, Збій(вид="дія", частина="протокол", поле="дія", що=repr(д.get("дія"))))
    return json.dumps(в, ensure_ascii=False)


def _кінець(сесія, збій, звіт=()):
    return {"сесія": сесія, "запити": [], "картки": [], "кінець": True, "збій": збій.в_json(), "звіт": list(звіт)}


def _перемикачі(дані):
    пм = {к: опис["типове"] for к, опис in ПЕРЕМИКАЧІ.items()}
    for к, в in (дані or {}).items():
        if к not in ПЕРЕМИКАЧІ or в not in ПЕРЕМИКАЧІ[к]["значення"]:
            return Збій(вид="перемикач", частина="протокол", поле=к, що=repr(в))
        пм[к] = в
    return пм


def _каталог(вхід):
    """Читає ту саму таблицю каталогу, що її вкладає збірка."""
    шлях = вхід.get("каталог")
    if isinstance(шлях, list):
        return шлях
    if not шлях:
        return ()
    from фід_каталог import база_прогону
    return база_прогону(шлях, ліміт_фото=0, кеш="кеш.json")["каталог"]


def почати(вхід):
    чужі = sorted(set(вхід) - ВХІД)
    if чужі:
        return _кінець(None, Збій(вид="схема", частина="протокол", поле=чужі[0], що="чужий ключ входу"))
    пм = _перемикачі(вхід.get("перемикачі"))
    if isinstance(пм, Збій):
        return _кінець(None, пм)
    try:
        каталог = _каталог(вхід)
        план_палітри = перекладач_паспорта.підготувати_палітру(вхід) if каталог else None
        с = ситуація.з_входу(вхід, план_палітри=план_палітри)
        профіль = знання.профіль_суду(вхід.get("профіль") or {})
    except (ValueError, OSError, KeyError, TypeError) as помилка:
        return _кінець(None, Збій(вид="вхід", частина="протокол", що=f"{type(помилка).__name__}: {помилка}"))
    розмова = вхід.get("розмова") or "без_розмови"
    _ОСТАННЯ[розмова] = max(_ОСТАННЯ.get(розмова, 0), с.версія)
    _ЛІЧИЛЬНИК[0] += 1
    сесія = f"я-{_ЛІЧИЛЬНИК[0]}"
    сід = int(вхід.get("сід") or 0)
    стан = {"розмова": розмова, "версія": с.версія, "сід": сід, "перемикачі": пм, "руки": {}, "чекає": {},
            "картки": {}, "звіт": []}
    _СЕСІЇ[сесія] = стан
    запити = []
    for р in РУКИ:
        стан["руки"][р] = руки.рука(р, с, сід + р - 1, пм, каталог,
                                      профіль, вхід.get("модель"), стан["звіт"])
        запити += _крок(сесія, р, None)
    return _відповідь(сесія, запити)


def _крок(сесія, рука, відп):
    """Один крок генератора руки: новий запит або картка руки (виняток — `Збій` на картці, не тиша)."""
    стан = _СЕСІЇ[сесія]
    генератор = стан["руки"][рука]
    try:
        вихід = next(генератор) if відп is None else генератор.send(відп)
    except StopIteration as кінець:
        стан["картки"][рука] = кінець.value
        return []
    except Exception as п:
        стан["картки"][рука] = картка_м.зі_збою(рука, стан["версія"], Збій(
            вид="виняток", частина="руки", що=f"{type(п).__name__}: {п}"))
        return []
    if not isinstance(вихід, Запит):
        стан["картки"][рука] = картка_м.зі_збою(рука, стан["версія"], Збій(
            вид="протокол", частина="руки", що=f"рука віддала {type(вихід).__name__}, а не запит"))
        return []
    стан["чекає"][вихід.ключ] = рука
    return [dict(вихід.в_json(), сесія=сесія, перемикачі=стан["перемикачі"])]


def відповідь(сесія, ключ, відп):
    стан = _СЕСІЇ.get(сесія)
    if стан is None:
        return _кінець(сесія, Збій(вид="сесія", частина="протокол", поле="сесія", що=repr(сесія)))
    рука = стан["чекає"].pop(ключ, None)
    if рука is None:
        return _кінець(сесія, Збій(вид="ключ", частина="протокол", поле="ключ", що=repr(ключ)))
    поточна = _ОСТАННЯ[стан["розмова"]]
    if стан["версія"] < поточна:
        стан["картки"][рука] = картка_м.зі_збою(рука, стан["версія"],
            Збій("застаріла_версія", "протокол", "версія_ситуації"))
        return _відповідь(сесія, [])
    return _відповідь(сесія, _крок(сесія, рука, відп))


def _відповідь(сесія, запити):
    стан = _СЕСІЇ[сесія]
    в = {"сесія": сесія, "запити": запити, "картки": [], "кінець": False, "звіт": [],
         "заглушки": {"ситуація": ситуація.НАРЯД, "пул": пул.НАРЯД, "запит": запит.НАРЯД, "розбір": розбір.НАРЯД,
                      "суд": суд.НАРЯД, "картка": картка_м.НАРЯД, "руки": руки.НАРЯД}}
    if len(стан["картки"]) < len(РУКИ):
        return в
    del _СЕСІЇ[сесія]
    в["кінець"] = True
    поточна = _ОСТАННЯ[стан["розмова"]]
    звіт = стан["звіт"] + [{"рука": р, "збій": к.збій.в_json()}
                            for р, к in sorted(стан["картки"].items()) if к.збій]
    if стан["версія"] < поточна:
        в["звіт"] = звіт + [{"заява": "застаріла_версія", "версія_ситуації": стан["версія"], "поточна": поточна}]
        return в
    позиції = random.Random(стан["сід"]).sample(range(len(РУКИ)), len(РУКИ))
    в["картки"] = sorted((картка_м.на_позиції(стан["картки"][р], п).в_json() for р, п in zip(РУКИ, позиції)),
                         key=lambda к: к["позиція"])
    в["звіт"] = звіт
    return в
