"""Нитки рук 1–4 (`ОПИС.md`, розділ 1): руки 1–2 — пул, запити, суд і картка ядра; руки 3–4 — модель без коду й каталогу."""
from collections import Counter
from dataclasses import replace
from functools import partial
import json

from . import картка, запит, пул, розбір, суд
from .поняття import Збій

НАРЯД = "Н3"  # руки 3–4 й режими перемикачів — залишок Н3 (PR, «Лишилось»)
_РЕЖИМ = {"вибір": "list", "запис": "повний", "частин": 1}


def _занести(звіт, рука, **дані):
    """Додає діагноз цієї руки до звіту."""
    звіт.append(dict(дані, рука=рука))


def _обмін(вид, кандидати, ситуація, профіль, модель, звіт, *, образи=(), вироки=None,
           дозволені=None, заміни=True, без_фото=False, перевірити_кадр=None, хибні=(), зламані=(), перемикачі=None):
    """Везе запит і за потреби повторює його один раз із назвою поля.

    Четвертий елемент — чому опис пішов без кадрів, коли в складу вони є (`картка.ПРИЧИНИ_БЕЗ_ФОТО`): кадри знімає
    саме ядро (межа запиту, повтор, прохання руки) чи вони не дійшли; картка називає саме цю причину.
    """
    збій = None
    фото_були = {}
    без_фото_чому = "after_failed_swap" if без_фото else None
    є_кадри = вид == "опис" and any(кандидати.записи[р["н"]].фото for о in образи for р in о.речі)
    for спроба in (1, 2):
        зап = запит.запит(вид, кандидати, ситуація, профіль, образи=образи, вироки=вироки,
                         спроба=спроба, збій=збій, без_фото=без_фото or спроба == 2, дозволені=дозволені,
                         заміни=заміни, модель=модель, перевірити_кадр=перевірити_кадр, хибні=хибні,
                         зламані=зламані)
        if isinstance(зап, Збій):
            збій = зап
            if спроба == 1 and (зап.дані or {}).get("photo_count"):
                без_фото_чому = "size_limit"
        else:
            if зап.знято:
                _занести(звіт, кандидати.рука, заява="pool_rows_trimmed", причина="estimated_context_budget",
                         крок=вид, скільки=зап.знято, межі=зап.розмір.get("trimmed_by", ()))
            if зап.розмір and зап.розмір["context_tokens"] is None:
                _занести(звіт, кандидати.рука, заява="model_context_unknown", крок=вид)
            відповідь = yield зап
            доставлені = відповідь.get("фото") or ()
            фото_були = {ф["n"]: ф["url"] for ф in зап.фото if ф["n"] in доставлені}
            відкинуті = [] if спроба == 2 and вид in ("складання", "ремонт") else None
            результат = розбір.прочитати(відповідь, вид, кандидати, спроба, образи,
                                          образи[0] if вид == "опис" else None, зап.номери, відкинуті)
            for помилка in відкинуті or ():
                _занести(звіт, кандидати.рука, крок=вид,
                         збій=Збій(помилка.вид, "розбір", помилка.поле, str(помилка), спроба=спроба).в_json())
            if вид == "вибір" and not isinstance(результат, Збій):
                результат = суд.вибір(результат, образи, вироки, ситуація.версія)
            if not isinstance(результат, Збій):
                return результат, зап.номери, фото_були, (без_фото_чому if є_кадри and not фото_були else None)
            збій = replace(результат, спроба=спроба)
            if спроба == 1 and зап.фото:
                без_фото_чому = ("not_delivered" if збій.вид == "кадри_не_дійшли"
                                 else "size_limit" if збій.частина == "запит"
                                 else "retry_after_model_error" if збій.частина == "модель"
                                 else "retry_after_format_error")
        _занести(звіт, кандидати.рука, крок=вид, збій=збій.в_json())
        if збій.частина == "запит" and збій.вид in ("вікно_моделі", "межа_транспорту"):
            має_фото = (збій.дані or {}).get("photo_count") if isinstance(зап, Збій) else зап.фото
            if not має_фото:
                break
    return збій, (), фото_були, None


def _вироки(образи, ситуація, кандидати, профіль, кеш, звіт, зламані=()):
    """Судить новий образ один раз і лишає діагноз кожного неприйнятого."""
    прийняті = []
    for образ in образи:
        if образ.ід not in кеш:
            кеш[образ.ід] = суд.судити(образ, ситуація, кандидати, профіль, зламані)
        вирок = кеш[образ.ід]
        if isinstance(вирок, Збій):
            _занести(звіт, образ.рука, крок="суд", збій=вирок.в_json())
        else:
            прийняті.append(образ)
    return tuple(прийняті)


def _після_ремонту(старі, нові, звіт, рука):
    """Лічить рішення ремонту та адресно називає заміни без причини."""
    лишились = {о.номер for о in нові}
    старий_за_номером = {о.номер: о for о in старі}
    for о in старі:
        if о.номер not in лишились:
            _занести(звіт, рука, заява="model_did_not_choose_for_repair", образ=о.ід)
    for о in нові:
        було = {р["н"] for р in старий_за_номером[о.номер].речі}
        пояснено = {з["річ"] for з in о.свідомі if з["заява"]}
        for р in о.речі:
            if р["н"] not in було | пояснено:
                _занести(звіт, рука, заява="replacement_without_reason", образ=о.ід, річ=р["н"])


def _заміна_з_фото(опис, фото, дозволені, образ, кандидати):
    """Пускає до повторного суду лише явно запропоновану заміну з показаного кадру."""
    зміна = опис.заміна
    забрати, взяти = зміна["item"], зміна.get("to")
    if (забрати not in фото or забрати not in опис.фото_не_те or взяти not in дозволені
            or not кандидати.записи[взяти].фото):
        return Збій("заміна_без_входу", "опис", "swap", "missing delivered photo or offered replacement")
    if кандидати.записи[забрати].слот != кандидати.записи[взяти].слот:
        return Збій("заміна_іншого_виду", "опис", "swap", "replacement is from another item kind")
    return розбір.замінити(образ, кандидати, забрати, взяти, "фото")


def _різниця_пулів(чистий, зламаний):
    """Де пул зі зламаним правилом інший, ніж справний того самого сіда: зняті, додані й переставлені речі за слотом."""
    def ряди(п):
        вих = {}
        for р in п.речі:
            вих.setdefault(п.записи[р["н"]].слот, []).append(р["ід"])
        return вих
    до, після = ряди(чистий), ряди(зламаний)
    вих = {}
    for слот in sorted(set(до) | set(після)):
        а, б = до.get(слот, []), після.get(слот, [])
        зняті, додані = len(set(а) - set(б)), len(set(б) - set(а))
        спільні = set(а) & set(б)
        переставлені = sum(1 for х, у in zip([і for і in а if і in спільні], [і for і in б if і in спільні]) if х != у)
        if зняті or додані or переставлені:
            вих[слот] = {"removed": зняті, "added": додані, "reordered": переставлені}
    причини = Counter(р["причина"] for р in зламаний.відкинуто) - Counter(р["причина"] for р in чистий.відкинуто)
    if причини:
        вих["rejected_by"] = dict(причини)
    return вих


def _різниця_запитів(а, б):
    """Ключі запиту складання (на тому самому пулі), що відрізняються від запиту зі справними правилами."""
    if isinstance(а, Збій) or isinstance(б, Збій):
        return ["request_failed"] if isinstance(а, Збій) != isinstance(б, Збій) else []
    да, дб = (json.loads(з.модель["messages"][0]["content"]) for з in (а, б))
    вих = []
    for к in sorted(set(да) | set(дб)):
        if к in ("pool",):
            continue
        if да.get(к) != дб.get(к):
            if isinstance(да.get(к), dict) and isinstance(дб.get(к), dict):
                вих += [f"{к}.{п}" for п in sorted(set(да[к]) | set(дб[к])) if да[к].get(п) != дб[к].get(п)]
            else:
                вих.append(к)
    return вих


def _дія_поломки(поломки, ситуація, сід, каталог, профіль, модель, кандидати):
    """Рука 2 міряє, де її поломки діють: пул і запит складання проти справних правил того самого сіда."""
    чистий = пул.зібрати(ситуація, 2, сід, каталог, профіль=профіль)
    зламані = tuple(поломки["коди"])
    справний_запит = запит.запит("складання", кандидати, ситуація, профіль, модель=модель)
    зламаний_запит = запит.запит("складання", кандидати, ситуація, профіль, модель=модель, зламані=зламані)
    return {"заява": "hand_2_breakage", "правила": tuple(поломки["правила"]), "коди": зламані,
            "місця": tuple(поломки["місця"]), "доступні": tuple(поломки.get("доступні") or ()),
            "без_входу": dict(поломки.get("без_входу") or {}),
            "пул": _різниця_пулів(чистий, кандидати), "запит": _різниця_запитів(справний_запит, зламаний_запит)}


def _суд_поломки(образи, вироки, ситуація, кандидати, профіль):
    """Заяви суду руки 2, яких справний суд того самого складу не дав, і навпаки (правило · код)."""
    вих = []
    for образ in образи:
        справний = суд.судити(образ, ситуація, кандидати, профіль)
        if isinstance(справний, Збій):
            continue
        до = {(з.правило, з.код) for з in справний.заяви}
        після = {(з.правило, з.код) for з in вироки[образ.ід].заяви}
        if до != після:
            вих.append({"outfit": образ.номер, "added": sorted("·".join(х) for х in після - до),
                        "removed": sorted("·".join(х) for х in до - після)})
    return вих


def рука(номер, ситуація, сід, перемикачі, каталог, профіль, модель, звіт, поломки=None):
    """Веде руку від пулу до картки, віддаючи запити транспортові.

    Руки 1 і 2 — один шлях Ч3–Ч7; у руки 2 поломки (`знання.жереб_поломок`) — значення на вході пулу, запиту й
    суду, а не окрема гілка. Руки 3–4 й режими, відмінні від `_РЕЖИМ`, — ще заглушка Н3."""
    версія = ситуація.версія
    if номер not in (1, 2) or перемикачі != _РЕЖИМ:
        return картка.зі_збою(номер, версія, Збій("частину_пише_Н3", "руки", "рука_або_режим"))
    if not каталог:
        return картка.зі_збою(номер, версія, Збій("нема_каталогу", "пул", "каталог"))
    зламані = tuple((поломки or {}).get("коди") or ()) if номер == 2 else ()
    if номер == 2 and not зламані:
        return картка.зі_збою(номер, версія, Збій("поломка_без_входу", "руки", "поломки",
                                                  json.dumps((поломки or {}).get("без_входу") or {}, ensure_ascii=False)))
    обмін = partial(_обмін, зламані=зламані, перемикачі=перемикачі)
    вироки_ = partial(_вироки, зламані=зламані)
    кандидати = пул.зібрати(ситуація, номер, сід, каталог, профіль=профіль, зламані=зламані)
    поломка = None
    if зламані:
        поломка = _дія_поломки(поломки, ситуація, сід, каталог, профіль, модель, кандидати)
        _занести(звіт, номер, **поломка)
        if not поломка["пул"] and not поломка["запит"] and not set(поломка["місця"]) & {"judge"}:
            return картка.зі_збою(номер, версія, Збій("поломка_не_діє", "руки", "поломки", "+".join(поломка["правила"])))
    _занести(звіт, номер, заява="pool_coverage", взято=len(кандидати.речі), знято=len(кандидати.відкинуто),
             слоти=кандидати.слоти, причини=dict(Counter(р["причина"] for р in кандидати.відкинуто)),
             нестача=кандидати.нема_в_каталозі, невідомі_межі=кандидати.невідомі_межі)
    for запис in кандидати.відкинуто:
        if запис["причина"] == "bad_record":
            _занести(звіт, номер, заява="bad_record", річ=запис["ід"], збої=запис["заяви"])

    образи, дозволені, _, _ = yield from обмін("складання", кандидати, ситуація, профіль, модель, звіт)
    if isinstance(образи, Збій):
        return картка.зі_збою(номер, версія, образи)
    вироки = {}
    образи = вироки_(образи, ситуація, кандидати, профіль, вироки, звіт)
    if not образи:
        return картка.зі_збою(номер, версія, Збій("суд_не_відбувся", "суд", "образи"))
    if поломка is not None:
        суд_змінено = _суд_поломки(образи, вироки, ситуація, кандидати, профіль)
        _занести(звіт, номер, заява="hand_2_breakage_judge", правила=поломка["правила"], суд=суд_змінено)
        if not (поломка["пул"] or поломка["запит"] or суд_змінено):
            return картка.зі_збою(номер, версія, Збій("поломка_не_діє", "руки", "поломки",
                                                      "+".join(поломка["правила"])))
    if any(суд.потребує_ремонту(вироки[о.ід]) for о in образи):
        нові, _, _, _ = yield from обмін("ремонт", кандидати, ситуація, профіль, модель, звіт,
                                      образи=образи, вироки=вироки, дозволені=дозволені)
        if not isinstance(нові, Збій):
            суджені = вироки_(нові, ситуація, кандидати, профіль, вироки, звіт)
            if суджені:
                _після_ремонту(образи, нові, звіт, номер)
                образи = суджені
    вибір, _, _, _ = yield from обмін("вибір", кандидати, ситуація, профіль, модель, звіт,
                                    образи=образи, вироки=вироки)
    if isinstance(вибір, Збій):
        return картка.зі_збою(номер, версія, вибір)

    обраний = next(о for о in образи if о.ід == вибір.обрано)
    вирок = вироки[обраний.ід]
    прийнято = вибір.прийнято
    опис, надіслано, фото, без_фото = yield from обмін("опис", кандидати, ситуація, профіль, модель, звіт,
                                             образи=(обраний,), вироки=вироки)
    хибні = картка.хибні_кадри(опис, кандидати, фото)
    if isinstance(опис, Збій) or not опис.заміна:
        return картка.зібрати(обраний, вирок, опис, кандидати, фото, прийнято, хибні=хибні, без_фото=без_фото)

    новий = _заміна_з_фото(опис, фото, надіслано, обраний, кандидати)
    if not isinstance(новий, Збій):
        новий_вирок = суд.судити(новий, ситуація, кандидати, профіль, зламані)
        if isinstance(новий_вирок, Збій):
            новий = новий_вирок
        elif any(з.значення["регістр"] == "гейт" for з in новий_вирок.заяви):
            новий = Збій("заміна_не_пройшла_суд", "суд", "swap", "replacement outfit has a gate finding")
        else:
            вироки[новий.ід] = новий_вирок
            додано = опис.заміна["to"]
            опис_заміни, _, кадри_заміни, _ = yield from обмін(
                "опис", кандидати, ситуація, профіль, модель, звіт,
                образи=(новий,), вироки=вироки, заміни=False, перевірити_кадр=додано, хибні=хибні)
            хибні_заміни = картка.хибні_кадри(опис_заміни, кандидати, кадри_заміни)
            річ = кандидати.записи[додано]
            кадр = (річ.ід, кадри_заміни.get(додано))
            if (not isinstance(опис_заміни, Збій) and not опис_заміни.заміна and опис_заміни.кадри_оцінено
                    and кадр[1] and кадр not in хибні_заміни):
                return картка.зібрати(новий, новий_вирок, опис_заміни, кандидати, кадри_заміни,
                                      хибні=хибні | хибні_заміни)
            хибні |= хибні_заміни
            новий = Збій("заміна_без_перевіреного_кадру", "опис", "swap",
                         "replacement needs a delivered, unflagged photo and a valid description")
    _занести(звіт, номер, крок="заміна", збій=новий.в_json())
    опис, _, фото, без_фото = yield from обмін("опис", кандидати, ситуація, профіль, модель, звіт,
                                               образи=(обраний,), вироки=вироки, заміни=False, без_фото=True,
                                               хибні=хибні)
    if not isinstance(опис, Збій) and опис.заміна:
        опис = Збій("повторна_заміна", "опис", "swap", "no photo swap was offered")
        _занести(звіт, номер, крок="опис", збій=опис.в_json())
    return картка.зібрати(обраний, вирок, опис, кандидати, фото, прийнято, хибні=хибні, без_фото=без_фото)
