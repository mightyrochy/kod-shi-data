"""Нитка однієї руки: складання → суд → вибір моделлю → опис → картка (`ОПИС.md`, розділ 1). Руки 2–4, свій сід
руки 2 й режими перемикачів по суті пише Н3.

Рука — генератор: віддає `Запит` і отримує відповідь, яку привіз показ; повертає `Картка` (зі збоєм теж).
Заглушка Н1 веде всі чотири руки тією самою ниткою, щоб протокол і перемикач були доведені до частин.
"""
from . import картка as картка_м, запит as запит_м, пул as пул_м, розбір, суд
from .поняття import Збій

НАРЯД = "Н3"


def рука(номер, ситуація, сід, перемикачі):
    версія = ситуація.версія
    пул = пул_м.зібрати(ситуація, номер, сід)
    образи = розбір.образи((yield запит_м.запит("складання", номер, ситуація, пул, {}, перемикачі)), номер, версія)
    if isinstance(образи, Збій):
        return картка_м.зі_збою(номер, версія, образи)
    вироки = {о.ід: суд.судити(о, ситуація) for о in образи}
    розібране = розбір.вибір((yield запит_м.запит("вибір", номер, ситуація, пул, {"образи": list(вироки)},
                                                 перемикачі)))
    вибір = розібране if isinstance(розібране, Збій) else суд.вибір(розібране, образи, версія)
    if isinstance(вибір, Збій):
        return картка_м.зі_збою(номер, версія, вибір)
    обраний = {о.ід: о for о in образи}[вибір.обрано]
    опис = розбір.опис((yield запит_м.запит("опис", номер, ситуація, пул,
                                           {"образ": обраний.ід, "речі": [р["н"] for р in обраний.речі]},
                                           перемикачі)))
    if isinstance(опис, Збій):
        return картка_м.зі_збою(номер, версія, опис)
    return картка_м.зібрати(обраний, вироки[обраний.ід], опис, номер)
