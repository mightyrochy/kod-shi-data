def _факти(ситуація):
    """Об'єднує два блоки фактів, зберігаючи їхні джерела."""
    return {**ситуація.сказала, **ситуація.виведено}


def _значення(факти, ключ):
    """Читає значення, доступне правилу."""
    факт = факти.get(ключ)
    return getattr(факт, "значення", НЕВІДОМО)


def _дорога_суха(факти):
    """Визначає відомий сухий випадок, де перевірка підошви не застосовна."""
    погода = _значення(факти, "смуга_погоди")
    опади = _значення(факти, "опади")
    return погода in ("mild", "warm", "hot", "помірно", "тепло", "спекотно") and опади in ("dry", "none", "сухо")


def _стан_країв(записи):
    """Зіставляє саме ті краї, які читає верхнє_довжина.краї."""
    from верхнє_довжина import довжина_виробу, розрив_країв
    from верхнє_реєстр import верхній as знайти_верхній

    верхній = знайти_верхній(записи)
    нижні = [р for р in записи if р["слот"] in ("сукня", "низ")]
    if верхній is None or not нижні:
        return {"стан": "нема_чого"}
    if any(розрив_країв(верхній, р)[0] is not None for р in нижні):
        return {"стан": "суджено"}
    if довжина_виробу(верхній)[0] is not None and all(довжина_виробу(р)[0] is not None for р in нижні):
        return {"стан": "немає_входу", "поле": "спільна довжина_виробу_точка"}
    return {"стан": "немає_входу", "поле": "довжина_виробу_см, довжина_виробу_точка"}


def _стан_каскаду(записи, краї):
    from верхнє_довжина import КАСКАД_СЛОТИ, довжина_виробу

    шари = [р for р in записи if р["слот"] in КАСКАД_СЛОТИ]
    if краї["стан"] == "нема_чого" or len(шари) < 3:
        return {"стан": "нема_чого"}
    точки = {точка for _, точка, _ in map(довжина_виробу, шари)}
    if None in точки:
        return {"стан": "немає_входу", "поле": "довжина_виробу_см, довжина_виробу_точка"}
    return _стан(True if len(точки) == 1 else None, ("спільна довжина_виробу_точка",))


def стан_правил(ситуація, речі, профіль):
    """Дає однакові позначки входу запиту й суду."""
    факти = _факти(ситуація)
    вихід = {}
    записи = [старий_запис(р) for р in речі]
    краї = _стан_країв(записи)
    for код, правило in ПРАВИЛА.items():
        if правило.get("перевірка") == "краї":
            вихід[код] = краї
            continue
        if правило.get("перевірка") == "каскад":
            вихід[код] = _стан_каскаду(записи, краї)
            continue
        слоти = правило.get("слоти")
        доречні = [р for р in речі if not слоти or р.слот in слоти]
        if (слоти and not доречні) or (код == "K-SHO-16" and _дорога_суха(факти)):
            вихід[код] = {"стан": "нема_чого"}
            continue
        поля = [п for п in правило.get("ситуація", ()) if _значення(факти, п) in _НЕМА]
        поля.extend(п for п in правило.get("профіль", ()) if профіль.get(п) in _НЕМА or not профіль.get(п))
        поля.extend(правило.get("зовнішнє", ()))
        if код == "R-CHEV-08":
            мета, зони = (_значення(факти, п) for п in ("мета", "мета_зони"))
            if мета in _НЕМА and (зони in _НЕМА or not зони):
                поля.append("мета або мета_зони")
        if код == "K-OUT-02" and not поля:
            from верхнє_довжина import нижче_коліна
            if any(нижче_коліна(старий_запис(р), профіль.get("висоти"))[0] is None for р in доречні):
                поля.append("довжина_рівень з відомим боком коліна")
        # Якщо бракує факту дня, відомостей про окремі речі ще не питаємо.
        if not поля:
            поля.extend(п for п in правило.get("річ", ())
                        if not доречні or any(_значення(р.поля, п) in _НЕМА for р in доречні))
        if код == "K-SIL-01" and not поля:
            from верхнє_довжина import довжина_виробу
            if not any(довжина_виробу(р)[0] is not None or
                       (р["слот"], р.get("крій")) == ("низ", "flared") and р.get("довжина_рівень")
                       for р in записи):
                поля.append("довжина_виробу або довжина кльошного низу")
        вихід[код] = {"стан": "немає_входу", "поле": ", ".join(поля)} if поля else {"стан": "суджено"}
    return вихід


def _стан(є, поля):
    if є is None:
        return {"стан": "немає_входу", "поле": ", ".join(поля)}
    return {"стан": "суджено" if є else "нема_чого"}


def _порівняння(ознаки, потрібних):
    """Лічить засвідчені учасники, відрізняючи відсутність від непевності."""
    відомо = sum(ознака is True for ознака in ознаки)
    невідомо = sum(ознака is None for ознака in ознаки)
    if відомо >= потрібних:
        return True
    return None if відомо + невідомо >= потрібних else False


def _входи_палітри(ситуація):
    from face_features import ознака_палітри, певно, сиве
    from місце_речі import волосся_біля_обличчя
    from palettes import ДОМІНАНТА_МІН, осі
    from палітра_нейтраль import бік_b_проти_людини
    from реєстр_намір import сміливі_наміри

    профіль = getattr(ситуація, "риси_портрета", None) or {}
    план = getattr(ситуація, "план_палітри", None) or {}
    вікна = True if план.get("вікна") else None
    позиція = осі(профіль, самозвіт=план.get("самозвіт"))["позиція"]
    голос = волосся_біля_обличчя(профіль)
    сивина = None
    if голос["місце"] is not None and певно(профіль, "сивина"):
        риса = ознака_палітри(профіль, голос["риса"])
        if риса["доступно"] and риса["значення"].get("C") is not None:
            сивина = сиве(риса["значення"])
    очі = бік_b_проти_людини(профіль)
    тон, хрома = позиція["hue"], позиція["chroma"]
    намір = старий_сценарій(ситуація).get("intent")
    мʼяка = (False if хрома is not None and хрома >= 0 or намір and намір not in сміливі_наміри()
             else True if вікна and хрома is not None and намір else None)
    return {"вікна": вікна, "сивина": сивина,
            "тон": None if тон is None else abs(тон) >= ДОМІНАНТА_МІН / 2,
            "очі": bool(очі["вхід"]) if очі.get("b_очей") is not None or очі.get("вхід") else None,
            "м’яка": мʼяка}


def _входи_складу(записи, профіль):
    from аксесуари_структура import акцентні_поверхні
    from колір_річ import має_колір, нейтраль_меж
    from формальність import інтервал_формальності
    from outfit import елементи
    from суд_інтерес import поверхня_речі, хрома_інтересу
    from верхнє_довжина import довжина_виробу

    принти, нейтралі = [], []
    for р in записи:
        принт = р.get("візерунок")
        принти.append(None if принт in _НЕМА else принт not in ("solid", "однотон"))
        нейтралі.append({"так": True, "ні": False}.get(нейтраль_меж(р)))
    кольорові_записи = [р for р in записи if має_колір(р)]
    акцентні = {е["слот"] for е in акцентні_поверхні(елементи(кольорові_записи))} if кольорові_записи else set()
    повний_вимір = all(р.get("lab") is not None for р in записи)
    поверхні = [поверхня_речі(р) for р in записи]
    інтерес = any(принт is True or нейтраль is False or поверхня
                  for принт, нейтраль, поверхня in zip(принти, нейтралі, поверхні))
    край = any(довжина_виробу(р)[0] is not None or р.get("довжина_рівень") for р in записи)
    хроми = [хрома_інтересу(dict(р, нейтраль=нейтраль)) if нейтраль is not None else "невідомо"
             for р, нейтраль in zip(записи, нейтралі)]
    відома_формула = (("невідомо" not in хроми and None not in принти)
                     or True in принти or sum(х == "так" for х in хроми) >= 2)
    return {
        "два_рівні": _порівняння([інтервал_формальності(р)[0] is not None or None for р in записи], 2),
        "блиск": True if any(р.get("блиск") is not None for р in записи) else None,
        "два_принти": _порівняння(принти, 2),
        "склад": bool(записи), "акценти": _порівняння([None if р is None else not р for р in нейтралі], 1),
        "край_тіла": True if край and профіль.get("висоти") else None,
        "реєстр": True if any(р.get("реєстр") not in _НЕМА for р in записи) else None,
        "нейтралі": _порівняння(нейтралі, 2),
        "два_акценти": True if len(акцентні) >= 2 else False if повний_вимір else None,
        "два_кольори": _порівняння([None if р is None else not р for р in нейтралі], 2),
        "один_принт": _порівняння(принти, 1),
        "інтерес": True if інтерес else None,
        "формула": True if відома_формула else None,
        "текстури": True if all(поверхні) or len({в for в in поверхні if в}) >= 2 else None,
    }


def стани_чекліста(ситуація, речі, профіль, стани):
    """Читає входи пунктів незалежно від наявності опису емітента."""
    from аксесуари_суд import входи_чекліста
    from дистанція import з_сценарію

    день = старий_сценарій(ситуація)
    факти = _факти(ситуація)
    записи = [старий_запис(р) for р in речі]
    входи = _входи_складу(записи, профіль)
    входи.update(_входи_палітри(ситуація))
    for режим, засвідчено in (("палітра_пара", входи["два_кольори"]), ("палітра_принт", входи["один_принт"])):
        входи[режим] = False if засвідчено is False else засвідчено and входи["вікна"]
    входи["дистанція"] = True if з_сценарію(день)["дистанція"] is not None else None
    аксесуари = входи_чекліста(записи, день.get("тривалість_год"), день.get("дорога_пішки_хв"))
    аксесуари["метал"] = any(р.get("метал") for р in записи)
    вихід = {}
    for група, пункти in ЧЕКЛІСТИ.items():
        for назва, пункт in пункти.items():
            режим, поля = пункт["перевірка"], пункт["поля"]
            if режим == "стан":
                стан = стани[поля[0]]
            elif режим == "день":
                відсутні = [п for п in поля if _значення(факти, п) in _НЕМА]
                стан = _стан(None, відсутні) if відсутні else _стан(True, ())
            elif режим == "або_день":
                стан = _стан(True if any(_значення(факти, п) not in _НЕМА for п in поля) else None, поля)
            elif режим == "аксесуари":
                вхід = пункт["поле"]
                є = False if вхід in аксесуари["не_стосується"] else True if аксесуари.get(вхід) else None
                стан = _стан(є, поля)
            elif режим == "немає_каналу":
                стан = _стан(None, поля)
            else:
                стан = _стан(входи[режим], поля)
            вихід[f"{група}.{назва}"] = стан
    return вихід


def правила_чекліста(стани, пункти):
    """Додає емітентів із перевіреним входом без повторного суду."""
    вихід = dict(стани)
    for група in ("excess", "plainness", "palette", "accessories", "context"):
        таблиця = ЧЕКЛІСТИ[група]
        for назва, пункт in таблиця.items():
            стан = пункти[f"{група}.{назва}"]
            for код in пункт["правила"]:
                вихід.setdefault(код, стан)
    return вихід


def чекліст(пункти, результати):
    """Додає кількість заяв до відомих станів пунктів."""
    вихід = {}
    for група, таблиця in ЧЕКЛІСТИ.items():
        for назва, пункт in таблиця.items():
            ключ = f"{група}.{назва}"
            стан = пункти[ключ]
            вихід[ключ] = (dict(стан, результат=sum(результати[код] for код in пункт["правила"])
                               if група != "context" else 0)
                            if стан["стан"] == "суджено" else стан)
    return вихід


def старий_сценарій(ситуація):
    """Передає старому суду лише відомі факти й головний етап."""
    факти = _факти(ситуація)
    вихід = {ключ: _значення(факти, поле) for поле, ключ in _ПОЛЯ_ДНЯ.items()
             if _значення(факти, поле) not in _НЕМА}
    наміри = ситуація.сказала["намір"]
    if наміри != НЕВІДОМО and наміри:
        вихід["intent"] = наміри[-1].значення
    етапи = ситуація.сказала["етапи"]
    if етапи != НЕВІДОМО and етапи:
        перший = етапи[0]
        for поле in ("місце", "надворі", "частина_дня"):
            значення = getattr(перший, поле)
            if значення not in _НЕМА:
                вихід[поле] = значення
    return вихід


def старий_запис(річ):
    """Будує запис суду лише зі значень Річ, зокрема без типового крою."""
    д = {"id": річ.ід, "слот": річ.слот}
    for поле, ключ in _ПОЛЯ_РЕЧІ.items():
        значення = _значення(річ.поля, поле)
        if значення not in _НЕМА:
            д[ключ] = значення
    довжина = річ.поля["довжина"]
    if довжина.джерело:
        д["довжина_джерело"] = довжина.межі if довжина.джерело == "код" else довжина.джерело
    вимір = _значення(річ.поля, "довжина_виробу")
    if isinstance(вимір, dict):
        д.update(вимір)
    ошатність = _значення(річ.поля, "ошатність")
    if isinstance(ошатність, (int, float)) and not isinstance(ошатність, bool):
        д["формальність"] = ошатність
    колір = річ.поля["колір"]
    if isinstance(колір.значення, dict) and колір.значення.get("lab"):
        д.update(колір_тип="вимір", lab=колір.значення["lab"], hex=колір.значення.get("hex"),
                 колір_ім=колір.значення.get("color"), колір_джерело=колір.джерело)
    elif колір.значення == НЕ_ПЕВНИЙ and "вікно" in колір.межі:
        д.update(колір_тип="інтервал", колір_не_вимір={"вікно": колір.межі["вікно"], "свідок": "shop_word"})
    return д


def команди_верхнього_шару(речі, ситуація):
    """Застосовує штатні команди лише до верхнього шару обраного складу."""
    верхня = next(((н, р) for н, р in речі if р.слот == "верхній_шар"), None)
    if верхня is None or верхня[1].поля["комір"].значення in _НЕМА:
        return []
    from верхнє_стан import команди_укладки

    записи = [dict(старий_запис(р), id=н, комір=р.поля["комір"].значення)
              if н == верхня[0] else dict(старий_запис(р), id=н) for н, р in речі]
    день = старий_сценарій(ситуація)
    команди = команди_укладки(записи, смуга_погоди=день.get("смуга_погоди"),
                              тривалість_год=день.get("тривалість_год"))
    return [{"item": верхня[0], "statements": [
        {"code": з["code"], "values": з["values"]}
        for з in [*команда.get("заяви", ()), *команда.get("ремонт_заяви", ())]]}
        for команда in команди]


def _знахідки(вихід):
    """Витягує знахідки за їхньою структурою, без читання пояснень."""
    if isinstance(вихід, dict):
        if "правило" in вихід and "заяви" in вихід:
            yield вихід
            return
        for значення in вихід.values():
            yield from _знахідки(значення)
    elif isinstance(вихід, (list, tuple)):
        for значення in вихід:
            yield from _знахідки(значення)


