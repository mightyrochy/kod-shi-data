def заяви(образ, ситуація, речі, профіль, стани, *, рядки_пулу=()):
    """Кличе старий суд раз і пропускає лише заяви, для яких є вхід."""
    from суд_від_моделі import перевірити_від_моделі

    каталог = [старий_запис(річ) for річ in речі]
    номери = {річ["н"]: річ["ід"] for річ in образ.речі}
    мітки = {"yes": "так", "no": "ні"}
    місця = {номери[рядок["item"]]: {к: мітки.get(в, в) for к, в in
             (("біля_обличчя", рядок.get("near_face")), ("видно", рядок.get("visible_under_coat")),
              ("розстебнуто", рядок.get("unbuttoned")), ("слова", рядок.get("words"))) if в is not None}
             for рядок in образ.носіння}
    частки = {р["ід"]: р["факти_рангу"]["window_share"] for р in рядки_пулу
              if р.get("факти_рангу", {}).get("window_share") is not None}
    кандидати = {}
    for річ in речі:
        кандидати.setdefault(річ.слот, []).append({"id": річ.ід, "частка_вікна": частки.get(річ.ід)})
    F = getattr(ситуація, "риси_портрета", None) or {}
    тіло = профіль if "профіль" in профіль else None
    вихід = перевірити_від_моделі(list(номери.values()), F, каталог, тіло,
                                  сценарій=старий_сценарій(ситуація), кандидати=кандидати, місця=місця, розриви=[])
    if вихід.get("перевірено") is not True:
        raise ValueError("старий суд не завершив перевірку складу")
    адреси = {ід: н for н, ід in номери.items()}
    бачили = set()
    for знахідка in _знахідки(вихід):
        правило = знахідка["правило"]
        if стани.get(правило, {}).get("стан") != "суджено":
            continue
        if знахідка.get("сила") in ("питання", "утримано") or знахідка.get("регістр") == "питання":
            continue
        учасники = знахідка.get("учасники") or {}
        н = tuple(адреси[ід] for ід in (учасники.get("речі") or знахідка.get("речі") or ()) if ід in адреси)
        for заява in знахідка["заяви"]:
            if not isinstance(заява, dict) or not заява.get("code"):
                continue
            значення = заява.get("values") or {}
            ключ = (правило, заява["code"], н, json.dumps(значення, sort_keys=True, ensure_ascii=False))
            if ключ not in бачили:
                бачили.add(ключ)
                yield правило, заява["code"], значення, н, знахідка.get("ремонт"), знахідка.get("регістр")
