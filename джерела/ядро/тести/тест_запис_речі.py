"""Ч2 · запис речі нового виду (наряд `Запис-речі-новий-вид`; корінь `Річ-запис-речі`).

Мірило (ґ): запис із новими полями читає ядро, а на записі каталогу без них правила кажуть «немає входу», а не типове.
Моделей тест не кличе: записи складені тестом за `дані/мітки_речі.json` і промптом `запис_речі.py`.
"""
import unittest

from ядро import знання, мітки, річ
from ядро.поняття import НЕВІДОМО, НЕ_ПЕВНИЙ, Ситуація, Факт

# Пара черевиків, як її записав би прохід К3 нового виду: вільний опис і мітки з джерелами.
ЧЕРЕВИКИ = {"id": "ж-тест-1", "слот": "взуття", "назва": "Черевики", "ціна": 3000, "мітки_речі": {
    "опис": "Чорні замшеві черевики з рифленою підошвою; хутро всередині видно на фото.",
    "мітки": {"слот": {"значення": "взуття", "джерело": "крамниця"},
              "тип": {"значення": "boots", "джерело": "крамниця"},
              "тканина": {"значення": "suede", "джерело": "крамниця"},
              "каблук": {"значення": НЕ_ПЕВНИЙ, "межі": [1, 4], "джерело": "фото"},
              "підошва": {"значення": "lug", "джерело": "фото"},
              "водостійкість": {"значення": "yes", "джерело": "крамниця"},
              "утеплення": {"значення": "warm", "джерело": "фото"},
              "крій": {"значення": "straight", "джерело": "фото"}}}}
ПАЛЬТО = {"id": "ж-тест-2", "слот": "верхній_шар", "назва": "Пальто", "ціна": 5000, "мітки_речі": {
    "опис": "Пряме вовняне пальто до коліна.",
    "мітки": {"тип": {"значення": "coat", "джерело": "крамниця"},
              "тканина": {"значення": "wool", "джерело": "крамниця"},
              "водостійкість": {"значення": "no", "джерело": "крамниця"},
              "утеплення": {"значення": "none", "джерело": "крамниця"}}}}


def _день():
    return Ситуація(1, {"подія": Факт("walk", "її_слова", "прогулянка"),
                        "смуга_погоди": Факт("cold", "її_слова", "холодно"),
                        "опади": Факт("snow", "її_слова", "сніг")}, {})


def _без_запису(рядок):
    """Той самий рядок каталогу без запису нового виду: лише тип і слот, як сьогодні."""
    return {"id": рядок["id"], "слот": рядок["слот"], "назва": рядок["назва"], "ціна": рядок["ціна"],
            "тип": {"взуття": "черевики", "верхній_шар": "пальто"}[рядок["слот"]]}


class ЗаписРечіНовогоВиду(unittest.TestCase):
    def test_мітки_запису_стають_полями_з_джерелом(self):
        р = річ.читати(ЧЕРЕВИКИ)
        self.assertEqual((р.слот, р.опис), ("взуття", ЧЕРЕВИКИ["мітки_речі"]["опис"]))
        self.assertEqual(р.поля["підошва"], Факт("lug", "фото"))
        self.assertEqual(р.поля["водостійкість"], Факт("yes", "крамниця"))
        self.assertEqual(р.поля["тканина"], Факт("замша", "крамниця"))
        self.assertEqual(р.поля["каблук"], Факт(НЕ_ПЕВНИЙ, "фото", межі=(1, 4)))
        # Крій поза слотом взуття — не мітка цієї речі: його нема, а не «прямий».
        self.assertEqual(р.поля["крій"].значення, НЕВІДОМО)
        self.assertEqual(р.збої, ())

    def test_тепло_шару_рахує_код_з_тканини_й_утеплення(self):
        пальто = річ.читати(ПАЛЬТО)
        self.assertEqual(пальто.поля["тепло_шару"], Факт("warm", "код", з_чого=("тканина", "утеплення")))
        # Взуттю тепла шару нема; бавовняне пальто з невідомим утепленням — «невідомо», а не «легке».
        self.assertEqual(річ.читати(ЧЕРЕВИКИ).поля["тепло_шару"].значення, НЕВІДОМО)
        бавовна = dict(ПАЛЬТО, мітки_речі={"мітки": {"тканина": {"значення": "cotton", "джерело": "крамниця"}}})
        self.assertEqual(річ.читати(бавовна).поля["тепло_шару"].значення, НЕВІДОМО)

    def test_правила_погоди_судять_із_записом_і_без_входу_без_нього(self):
        день = _день()
        з_записом = знання.стан_правил(день, [річ.читати(ЧЕРЕВИКИ), річ.читати(ПАЛЬТО)], {})
        без = знання.стан_правил(день, [річ.читати(_без_запису(ЧЕРЕВИКИ)), річ.читати(_без_запису(ПАЛЬТО))], {})
        for код in ("K-WEA-01", "K-WEA-06", "K-WEA-07"):
            self.assertEqual(з_записом[код], {"стан": "суджено"}, код)
        self.assertEqual(без["K-WEA-06"], {"стан": "немає_входу", "поле": "підошва"})
        self.assertEqual(без["K-WEA-07"], {"стан": "немає_входу", "поле": "утеплення"})
        self.assertEqual(без["K-WEA-01"], {"стан": "немає_входу", "поле": "тепло_шару, водостійкість"})

    def test_бита_мітка_невідома_із_заявою(self):
        битий = dict(ЧЕРЕВИКИ, мітки_речі={"мітки": {"підошва": {"значення": "резина", "джерело": "фото"},
                                                    "водостійкість": {"значення": "yes", "джерело": "фото"}}})
        р = річ.читати(битий)
        self.assertEqual((р.поля["підошва"].значення, р.поля["водостійкість"].значення), (НЕВІДОМО, НЕВІДОМО))
        self.assertEqual(sorted(з.поле for з in р.збої), ["мітки_речі.водостійкість", "мітки_речі.підошва"])

    def test_відсутність_утеплення_лише_зі_слів_крамниці(self):
        # Фото відсутності утеплювача не доводить: «none» з фото — невідомо із заявою; хутро з фото — тепле.
        з_фото = dict(ЧЕРЕВИКИ, мітки_речі={"мітки": {"утеплення": {"значення": "none", "джерело": "фото"}}})
        р = річ.читати(з_фото)
        self.assertEqual(р.поля["утеплення"].значення, НЕВІДОМО)
        self.assertEqual([з.поле for з in р.збої], ["мітки_речі.утеплення"])
        self.assertEqual(мітки.мітка("утеплення", {"в": "warm", "дж": "фото"}),
                         ({"значення": "warm", "джерело": "фото"}, None))
        import запис_речі
        self.assertIn("Only from the shop's words: none.", запис_речі.промпт("назва: черевики", 2)[1])

    def test_кожна_мітка_має_читача_і_поле_ядра(self):
        from ядро.поняття import ПОЛЯ_РЕЧІ
        for поле in мітки.МІТКИ:
            with self.subTest(поле=поле):
                self.assertTrue(мітки.читачі(поле))
                self.assertIn(поле, (*ПОЛЯ_РЕЧІ, "слот", "опис"))

    def test_промпт_з_того_самого_визначення(self):
        import запис_речі
        _, текст = запис_речі.промпт("назва: черевики", 2)
        for поле in мітки.ЗАПИТАНІ:
            self.assertIn(f'"{поле}"', текст)
        self.assertNotIn('"тепло_шару"', текст)
        # Вишивка й мереживо — лише в описі: кодів візерунка для них нема ні в мітці, ні в промпті.
        self.assertNotIn("embroidery", мітки.коди("візерунок"))
        self.assertNotIn("lace_motif", текст)


class КолірЗапису(unittest.TestCase):
    """Мітка «колір» (наряд `Запис-речі-колір-мітка`): читач зводить ясну форму до визначення, а хибне відкидає."""

    def test_понад_чотири_коди_основний_і_три_найбільші(self):
        from ядро import відтінки
        в = [{"код": "black", "частка": 0.3}, {"код": "strong_orange_yellow", "частка": 0.25},
             {"код": "strong_red", "частка": 0.1}, {"код": "moderate_purplish_pink", "частка": 0.2},
             {"код": "moderate_green", "частка": 0.15}]
        мітка, збій = відтінки.перевірити({"в": в, "принт": True}, "фото")
        self.assertIsNone(збій)
        self.assertEqual([к["код"] for к in мітка["значення"]],
                         ["black", "strong_orange_yellow", "moderate_purplish_pink", "moderate_green"])

    def test_один_код_уся_річ(self):
        from ядро import відтінки
        мітка, збій = відтінки.перевірити({"в": [{"код": "vivid_red", "частка": 0.0}]}, "фото")
        self.assertIsNone(збій)
        self.assertEqual(мітка["значення"], [{"код": "vivid_red", "частка": 1}])

    def test_вигаданий_код_і_нульовий_основний_збій(self):
        from ядро import відтінки
        for в in ([{"код": "vivid_red", "частка": 0.9}, {"код": "metal_placeholder", "частка": 0.1}],
                  [{"код": "vivid_red", "частка": 0}, {"код": "black", "частка": 1}],
                  [{"код": "vivid_red", "частка": None}, {"код": "black", "частка": 0.5}]):
            мітка, збій = відтінки.перевірити({"в": в}, "фото")
            self.assertIsNone(мітка)
            self.assertTrue(збій)


class ВкластиЗаписиТест(unittest.TestCase):
    """Крок увімкнення (наряд `Запис-речі-прохід-сцен`, п.4): запис нового виду вкладає лише перемикач, інших рядків не чіпає."""

    def test_вкласти_лише_речі_із_записом(self):
        from ядро.записи_речей import вкласти
        запис = {"ж-1@к": {"опис": "Опис.", "мітки": {"колір": {"значення": [{"код": "black", "частка": 1.0}], "джерело": "фото"}}}}
        каталог = [{"id": "ж-1@к", "слот": "взуття", "назва": "А", "ціна": 1}, {"id": "ж-2@к", "слот": "взуття", "назва": "Б", "ціна": 2}]
        вихід = вкласти(каталог, запис)
        self.assertEqual(вихід[0]["мітки_речі"]["опис"], "Опис.")
        self.assertNotIn("мітки_речі", вихід[1])
        self.assertNotIn("мітки_речі", каталог[0])

    def test_слот_із_запису_не_вкладається(self):
        from ядро.записи_речей import вкласти
        запис = {"ж-1@к": {"опис": "О.", "мітки": {"слот": {"значення": "низ", "джерело": "фото"}, "тип": {"значення": "trousers", "джерело": "фото"}}}}
        вихід = вкласти([{"id": "ж-1@к", "слот": "комплект", "назва": "А", "ціна": 1}], запис)
        self.assertNotIn("слот", вихід[0]["мітки_речі"]["мітки"])
        self.assertIn("тип", вихід[0]["мітки_речі"]["мітки"])

    def test_перемикач_типово_вимкнений(self):
        from ядро.протокол import ПЕРЕМИКАЧІ
        self.assertEqual(ПЕРЕМИКАЧІ["записи_речі"]["типове"], "без")


if __name__ == "__main__":
    unittest.main()
