    def test_групи_турніру_рівні_й_повні(self):
        """Ч3: групи слота — ≤ 10 речей, рівні з точністю до одної, разом — усі речі слота; слот із ≤ 2 речами груп не має."""
        from ядро import пул
        кандидати = пул.зібрати(_ситуація(), 1, 7, _турнірний_каталог() + [_запис(f"bagx{і}", "сумка") for і in range(10)])
        групи = пул.групи_турніру(кандидати, кандидати.сід)
        сумки = [г for г in групи if г.startswith("bag")]
