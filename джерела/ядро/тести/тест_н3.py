def _картки(в):
    return {к["рука"]: cls.з_json(к) for вид, cls in (("картки", Картка), ("відмови", ВідмоваРуки))
            for к in в.get(вид, ())}


def _складач(з):
    """Заглушка моделі рук 1–2 над будь-яким пулом: перша річ кожного виду, ремонт лишає склад, вибір — перший."""
    тіло = json.loads(з["модель"]["messages"][0]["content"])
    def відп(**поля):
        return {"текст": json.dumps({"version": "1", **поля}, ensure_ascii=False)}
    if з["вид"] == "складання":
        к = тіло["pool"]["cols"]
        види = {}
        for р in тіло["pool"]["rows"]:
            види.setdefault(р[к.index("kind")], р[к.index("n")])
        return відп(outfits=[{"id": "o1", "items": list(види.values())}])
    if з["вид"] == "ремонт":
        return відп(outfits=[{"id": о["id"], "items": о["items"]} for о in тіло["verdict"]])
    if з["вид"] == "вибір":
        return відп(chosen=тіло["verdict"][0]["id"])
    if з["вид"] == "турнір":
        к = тіло["groups"]["cols"].index("n")
        return відп(winners=[{"group": г, "items": [р[к] for р in рр[-2:]]} for г, рр in тіло["groups"]["groups"].items()])
    if з["вид"] == "оцінка":
        return відп(ratings=_оцінки(тіло))
    return dict(відп(text="Fixture outfit.", about_items=[{"n": р["n"], "text": "Fixture item."}
                                                          for р in тіло["outfit"]["items"]]),
                фото=[ф["n"] for ф in з["фото"]])


def _оцінки(тіло):
    """Оцінка заглушки: кожна річ «fits», крім останньої речі виду, де їх більше одної, — «colour»."""
    к = тіло["items"]["cols"]
    рядки = тіло["items"]["rows"]
    останні = {}
    for р in рядки:
        останні.setdefault(р[к.index("kind")], []).append(р[к.index("n")])
    не = {нн[-1] for нн in останні.values() if len(нн) > 1}
    return [{"n": р[к.index("n")], "verdict": "colour" if р[к.index("n")] in не else "fits"} for р in рядки]


def _з_планом(ситуація, план):
    """Та сама Ситуація з планом палітри, як її дає Ч1 (`ситуація.з_профілем`)."""
    object.__setattr__(ситуація, "план_палітри", план)
    return ситуація


