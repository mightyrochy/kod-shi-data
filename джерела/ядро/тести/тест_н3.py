        турнірів_руки_1 = [з for з in журнал["запити"] if з["рука"] == 1 and з["вид"] == "турнір"]
        self.assertEqual(len(турнірів_руки_1), руки._РАУНДІВ_ТУРНІРУ)   # усі групи — одна порція (19 ≤ 60), далі пояс
