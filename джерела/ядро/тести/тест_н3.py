def _картки(в):
    return {к["рука"]: Картка.з_json(к) for к in в["картки"]}


def _складач(з):
    """Заглушка моделі рук 1–2 над будь-яким пулом: перша річ кожного виду, ремонт лишає склад, вибір — перший."""
    тіло = json.loads(з["модель"]["messages"][0]["content"])
    def відп(**поля):
        return {"текст": json.dumps({"version": "1", **поля}, ensure_ascii=False)}
    if з["вид"] == "складання":
        к = тіло["pool"]["cols"]
        види = {}
        for р in тіло["pool"]["rows"]:
            види.setdefault(р[к.index("kind")], р[к.index("n")])
        return відп(outfits=[{"id": "o1", "items": list(види.values())}])
    if з["вид"] == "ремонт":
        return відп(outfits=[{"id": о["id"], "items": о["items"]} for о in тіло["verdict"]])
    if з["вид"] == "вибір":
        return відп(chosen=тіло["verdict"][0]["id"])
    return dict(відп(text="Fixture outfit.", about_items=[{"n": р["n"], "text": "Fixture item."}
                                                          for р in тіло["outfit"]["items"]]),
                фото=[ф["n"] for ф in з["фото"]])


def _з_планом(ситуація, план):
    """Та сама Ситуація з планом палітри, як її дає адаптер паспорта (`перекладач_паспорта`)."""
    object.__setattr__(ситуація, "план_палітри", план)
    return ситуація


class РукиБезКоду(TestCase):
    """П.3 наряду: руки 3–4 — модель без коду й каталогу; промпт — чинний, байт у байт; Ч4 міряє, Ч5 розбирає."""

    ПРОФІЛЬ = {"колір": {"шкіра": "#c8a48c", "волосся": ["#3b2a20", "#4a3526"], "очі": "#625448"},
               "мірки": {"зріст": 164.4, "обхвати": {"груди": 92, "талія": 74, "стегна": 99}}}

    def _дріт(self, рука, ситуація, профіль=None):
        з = запит.запит_без_коду("образ", рука, 7, ситуація, профіль if профіль is not None else self.ПРОФІЛЬ,
                                 модель={"вікно": 200_000})
        return з, з.модель["messages"][0]["content"]

    def test_промпт_руки_байт_у_байт(self):
        """Ядро складає промпт руки 3 і 4 із даних так само, як чинний `руки_без_коду.промпт_руки`."""
        import руки_без_коду as Р

        основа = {"colour": "blue #1f3a93", "chosen_by": "her"}
        for рука, план in ((3, None), (4, None), (3, {"поля_дроту": {"base": основа}}),
                           (4, {"поля_дроту": {"base": основа}})):
            with self.subTest(рука=рука, основа=bool(план)):
                с = _з_планом(_ситуація(), план)
                _, текст = self._дріт(рука, с)
                дані = json.loads(текст)
                with patch.object(Р, "головний_колір", lambda _в: дані.get("main_color")):
                    чинний = Р.промпт_руки(str(рука), дані["case"], "", {"база": 1} if план else None, None,
                                           дані.get("person"))
                self.assertEqual(текст, чинний)
                self.assertEqual("person" in дані, рука == 3)
                self.assertNotIn("pool", дані)

    def test_основа_лише_її_вибір(self):
        """П-7: основу, яку обрав код чи стилістка, руки 3–4 не бачать; її вибір — бачать."""
        for хто, є in (("her", True), ("conversation", True), ("code_rank", False), ("stylist", False)):
            with self.subTest(хто=хто):
                с = _з_планом(_ситуація(), {"поля_дроту": {"base": {"colour": "blue", "chosen_by": хто}}})
                self.assertEqual("main_color" in json.loads(self._дріт(4, с)[1]), є)

    def test_одна_міра_вікна(self):
        """Запит руки 3 міряє та сама міра, що в руки 1: понад вікно — `Збій` до виклику моделі."""
        з, _ = self._дріт(3, _ситуація())
        self.assertEqual(з.розмір["limit_source"], "model_context")
        тісно = запит.запит_без_коду("образ", 3, 7, _ситуація(), self.ПРОФІЛЬ, модель={"вікно": 4_100})
        self.assertEqual((тісно.вид, тісно.частина), ("вікно_моделі", "запит"))

    def test_картка_без_крамниць_і_цін_про_той_самий_склад(self):
        """Наскрізно через протокол: картка руки 3–4 — описані речі без крамниць, цін і фото; вирок і пояснення
        — про той самий склад; чекліст — «немає входу: каталог»."""
        в, журнал = обвязка.прогнати(протокол, обвязка.вхід_с5(розмова="н3-без-коду"),
                                     обвязка.записаний(обвязка.тексти_с5()))
        кк = _картки(в)
        for р in (3, 4):
            with self.subTest(рука=р):
                к = кк[р]
                self.assertIsNone(к.збій)
                self.assertEqual([р_["назва"] for р_ in к.речі],
                                 ["Cocktail dress", "Heeled sandals", "Clutch", "Drop earrings", "Thin bracelet"])
                self.assertTrue(all("крамниця" not in р_ and "ціна" not in р_ and "фото" not in р_ for р_ in к.речі))
                self.assertIsNone(к.разом)
                self.assertEqual(к.вирок, к.образ)
                self.assertTrue(к.опис_en.startswith("Cocktail dress"))
        вид = [з["вид"] for з in журнал["запити"] if з["рука"] in (3, 4)]
        self.assertEqual(sorted(вид), ["образ", "образ", "перелік", "перелік"])

    def test_не_за_схемою_один_повтор_і_збій(self):
        """Перелік не за схемою — один повтор того самого промпту; удруге — `Збій` на картці, інші руки на місці."""
        тексти = dict(обвязка.тексти_с5(), перелік='{"is_outfit":"yes","items":[{"name":"x","slot":"cape"}]}')
        в, журнал = обвязка.прогнати(протокол, обвязка.вхід_с5(розмова="н3-схема"), обвязка.записаний(тексти))
        кк = _картки(в)
        self.assertEqual((кк[3].збій.частина, кк[3].збій.поле), ("розбір", "items[0].slot"))
        переліки = [з for з in журнал["запити"] if з["рука"] == 3 and з["вид"] == "перелік"]
        self.assertEqual(len(переліки), 2)
        self.assertEqual(переліки[0]["модель"], переліки[1]["модель"])
        self.assertEqual(sorted(кк), [1, 2, 3, 4])   # рука 1 тут без каталогу — її збій свій, не з переліку
        self.assertEqual(кк[1].збій.частина, "пул")

    def test_опис_не_образ_один_повтор_руки(self):
        """«Не образ» від переліку — один повтор руки тим самим промптом; удруге — чесний `Збій`, а не картка."""
        тексти = dict(обвязка.тексти_с5(), перелік='{"is_outfit":"no","items":[]}')
        в, журнал = обвязка.прогнати(протокол, обвязка.вхід_с5(розмова="н3-не-образ"), обвязка.записаний(тексти))
        self.assertEqual(_картки(в)[4].збій.вид, "не_образ")
        self.assertEqual([з["вид"] for з in журнал["запити"] if з["рука"] == 4], ["образ", "перелік"] * 2)
        self.assertIn({"заява": "description_not_outfit", "повтор": 1, "рука": 4}, в["звіт"])

    def test_проза_без_мітки_форми(self):
        """Ч5 знімає лише код форми на початку прози; порожня проза — `Збій`, не картка."""
        self.assertEqual(розбір.проза({"текст": "**OUTFIT_TEXT:**\nDress"}), "Dress")
        self.assertEqual(розбір.проза({"текст": "Dress, OUTFIT_TEXT"}), "Dress, OUTFIT_TEXT")
        self.assertEqual(розбір.проза({"текст": " OUTFIT_TEXT \n "}).вид, "порожньо")

    def test_вирок_без_коду_всі_пункти_без_входу(self):
        образ = розбір.перелік({"текст": обвязка.текст_запису("с5_весілля_сестри", 8)}, 3, 1)
        вирок = суд.без_коду(образ, _ситуація())
        self.assertEqual(вирок.заяви, ())
        self.assertTrue(вирок.чекліст)
        self.assertEqual({(с["стан"], с["поле"]) for с in вирок.чекліст.values()}, {("немає_входу", "каталог")})


class Т17_Рука2(TestCase):
    """Т17: сід руки 2 ≠ сіду руки 1; пул чи запит руки 2 інший там, де діє зламане правило; інакше — `Збій`."""

    def _прогнати(self, розмова, поломки=None):
        вхід = обвязка.вхід_с5(розмова=розмова, каталог=_складений_каталог(), паспорт={"нагода": "everyday"})
        if поломки is None:
            return обвязка.прогнати(протокол, вхід, _складач)
        with patch.object(знання, "жереб_поломок", return_value=поломки):
            return обвязка.прогнати(протокол, вхід, _складач)

    def test_рука2_свій_сід_і_поломка_діє(self):
        в, журнал = self._прогнати("т17")
        сіди = {з["рука"]: з["сід"] for з in журнал["запити"]}
        self.assertNotEqual(сіди[1], сіди[2])
        дія, = [з for з in в["звіт"] if з.get("заява") == "hand_2_breakage"]
        суд_ = [з for з in в["звіт"] if з.get("заява") == "hand_2_breakage_judge"]
        діє = bool(дія["пул"] or дія["запит"] or any(з["суд"] for з in суд_))
        к2 = _картки(в)[2]
        self.assertEqual(к2.збій is not None and к2.збій.вид == "поломка_не_діє", not діє, (дія, суд_, к2.збій))

    def test_поломка_без_дії_не_рука1_удруге(self):
        """Зламане правило не міняє ні пулу, ні запиту, ні суду (K-BOD-02 без рівнів, як с4 у 16958) — `Збій`."""
        в, журнал = self._прогнати("т17-не-діє", {"правила": ("K-BOD-02",), "коди": ("K-BOD-02",),
                                                   "місця": ("pool",), "доступні": ("K-BOD-02",), "без_входу": {}})
        к2 = _картки(в)[2]
        self.assertEqual((к2.збій.вид, к2.збій.що), ("поломка_не_діє", "K-BOD-02"))
        self.assertFalse([з for з in журнал["запити"] if з["рука"] == 2])
        self.assertIsNone(_картки(в)[1].збій)

    def test_жереб_без_входу_каже_чого_бракує(self):
        в, _ = self._прогнати("т17-без-входу", {"правила": (), "коди": (), "місця": (), "доступні": (),
                                                "без_входу": {"K-BOD-02": "мірки.рівні"}})
        к2 = _картки(в)[2]
        self.assertEqual(к2.збій.вид, "поломка_без_входу")
        self.assertIn("мірки.рівні", к2.збій.що)


class Т32_КарткиРазом(TestCase):
    def test_картки_разом(self):
        """Т32: руки відповідають у різному порядку (рука 1 — першою, рука 3 — останньою); показ отримує чотири
        картки одним повідомленням, і жодне раніше не несе картки."""
        for порядок in ((1, 2, 4, 3), (3, 4, 2, 1)):
            with self.subTest(порядок=порядок):
                в = обвязка.почати(протокол, обвязка.вхід_с5(розмова=f"т32-{порядок}"))
                відповісти = обвязка._руки_без_коду(обвязка.записаний(обвязка.тексти_с5()))
                черга, повідомлення = list(в["запити"]), [в]
                while not повідомлення[-1]["кінець"]:
                    черга.sort(key=lambda з: порядок.index(з["рука"]))
                    з = черга.pop(0)
                    вв = json.loads(протокол.виклик(json.dumps({"дія": "відповідь", "сесія": з["сесія"],
                                                               "ключ": з["ключ"], "відповідь": відповісти(з)},
                                                              ensure_ascii=False)))
                    черга += вв["запити"]
                    повідомлення.append(вв)
                self.assertEqual([len(п["картки"]) for п in повідомлення], [0] * (len(повідомлення) - 1) + [4])
                self.assertEqual(sorted(к["рука"] for к in повідомлення[-1]["картки"]), [1, 2, 3, 4])
