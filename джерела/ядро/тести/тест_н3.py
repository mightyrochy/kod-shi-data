class Т32_КарткиРазом(TestCase):
    def test_картки_разом(self):
        """Т32: руки відповідають у різному порядку (рука 1 — першою, рука 3 — останньою); показ отримує чотири
        картки одним повідомленням, і жодне раніше не несе картки."""
        for порядок in ((1, 2, 4, 3), (3, 4, 2, 1)):
            with self.subTest(порядок=порядок):
                в = обвязка.почати(протокол, обвязка.вхід_с5(розмова=f"т32-{порядок}"))
                відповісти = обвязка._руки_без_коду(обвязка.записаний(обвязка.тексти_с5()))
                черга, повідомлення = list(в["запити"]), [в]
                while not повідомлення[-1]["кінець"]:
                    черга.sort(key=lambda з: порядок.index(з["рука"]))
                    з = черга.pop(0)
                    вв = json.loads(протокол.виклик(json.dumps({"дія": "відповідь", "сесія": з["сесія"],
                                                               "ключ": з["ключ"], "відповідь": відповісти(з)},
                                                              ensure_ascii=False)))
                    черга += вв["запити"]
                    повідомлення.append(вв)
                self.assertEqual([len(_картки(п)) for п in повідомлення], [0] * (len(повідомлення) - 1) + [4])
                self.assertEqual(sorted(_картки(повідомлення[-1])), [1, 2, 3, 4])


class Т49_РежимиПеремикачів(TestCase):
    """Т49 справжніми руками ядра (не підставною рукою транспорту): кожен режим дає `Картку` без старого шляху
    (рішення менеджера 26.11, РЕЗУЛЬТАТ §6.2). «Турнір» — групи Ч3, запити турніру Ч4 одним повідомленням, фінал —
    складання над переможцями; «оцінка» — оцінка кожної речі пулу одним повідомленням, фінал — складання моделлю над
    речами «fits»; «запис» — той самий запит обома значеннями."""

    def test_режими_перемикачів_рук_на_ядрі(self):
        import itertools

        for вибір, запис, частин in itertools.product(("list", "assess", "tournament"), ("повний", "короткий"),
                                                      (1, 2, 3)):
            with self.subTest(вибір=вибір, запис=запис, частин=частин):
                пм = {"вибір": вибір, "запис": запис, "частин": частин}
                каталог = _турнірний_каталог() if вибір == "tournament" else _складений_каталог()
                вхід = обвязка.вхід_с5(розмова=f"т49-{вибір}-{запис}-{частин}", каталог=каталог,
                                       факти={"подія": "everyday"}, перемикачі=пм)
                перша = обвязка.почати(протокол, вхід)
                в, журнал = обвязка.довезти(протокол, перша, _складач)
                кк = _картки(в)
                self.assertEqual(sorted(кк), [1, 2, 3, 4])
                self.assertTrue(all(з["перемикачі"] == пм for з in журнал["запити"]))
                self.assertTrue(all(кк[р].збій is None for р in (3, 4)))
                self.assertIsNone(кк[1].збій)
                if вибір == "assess":
                    self.assertTrue(перша["запити"])
                    self.assertTrue(all(з["вид"] == "оцінка" for з in перша["запити"] if з["рука"] in (1, 2)))
                    оцінка, = [з for з in в["звіт"] if з.get("заява") == "assessment" and з["рука"] == 1]
                    self.assertEqual((оцінка["оцінено"], оцінка["не_оцінено"], оцінка["чужі"]), (оцінка["було"], [], []))
                    self.assertLess(оцінка["у_фіналі"], оцінка["було"])
                    self.assertEqual(оцінка["у_фіналі"], оцінка["причини"]["fits"])
                    складання = [з for з in журнал["запити"] if з["рука"] == 1 and з["вид"] == "складання"]
                    self.assertEqual(len(складання), частин)
                    рядків = sum(len(json.loads(з["модель"]["messages"][0]["content"])["pool"]["rows"])
                                 for з in складання)
                    self.assertLessEqual(рядків, оцінка["у_фіналі"] * частин)   # слот, де речей < частин, — у кожній
                    continue
                if вибір == "tournament":
                    self.assertTrue(перша["запити"])
                    self.assertTrue(all(з["вид"] == "турнір" for з in перша["запити"] if з["рука"] == 1))
                    турнір, = [з for з in в["звіт"] if з.get("заява") == "tournament" and з["рука"] == 1]
                    self.assertGreater(турнір["груп"], 0)
                    self.assertLess(турнір["у_фіналі"], турнір["було"])
                    self.assertEqual(турнір["без_переможців"], [])
                    складання = [з for з in журнал["запити"] if з["рука"] == 1 and з["вид"] == "складання"]
                    self.assertEqual(len(складання), частин)
                    рядків = sum(len(json.loads(з["модель"]["messages"][0]["content"])["pool"]["rows"])
                                 for з in складання)
                    self.assertLessEqual(рядків, турнір["у_фіналі"] * частин)
                    continue
                складання = [з for з in перша["запити"] if з["рука"] == 1 and з["вид"] == "складання"]
                self.assertEqual(len(складання), частин)   # частини — одним повідомленням, одночасно
                if частин > 1:
                    self.assertTrue(кк[1].образ.startswith("ч"))
                    частини, = [з for з in в["звіт"] if з.get("заява") == "pool_parts"]
                    self.assertEqual(len(частини["речей"]), частин)
        в = обвязка.почати(протокол, обвязка.вхід_с5(перемикачі={"вибір": "навмання"}))
        self.assertTrue(в["кінець"])
        self.assertEqual((в["збій"]["вид"], в["збій"]["поле"]), ("перемикач", "вибір"))

    def test_оцінка_повнота_й_без_пасує(self):
        """«Оцінка»: річ, яку модель пропустила, іде наступним раундом лише вона; після останнього раунду — у складання
        не йде, і звіт її називає. Жодна річ не «fits» — чесний `Збій` на картці, а не образ із решти."""
        пропущена = []

        def мовчить_про_річ(з):
            if з["вид"] != "оцінка":
                return _складач(з)
            тіло = json.loads(з["модель"]["messages"][0]["content"])
