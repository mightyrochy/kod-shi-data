"""Ш · Н1: протокол «ядро просить — показ везе» на заглушці моделі (`РЕЗУЛЬТАТ.md`, §4: Т33, Т34, Т35, Т47, Т49;
`ОПИС.md`, розділ 5) і наскрізна нитка `с5:6` від «почати» до `Картка` через частини-заглушки (наряд Н1, п.6)."""
import itertools
import json
import os
import subprocess
import sys
import unittest
from unittest.mock import patch

from ядро import протокол, руки
from ядро.поняття import Картка, Пул, Вирок, Запит, ХибнеЗначення
from ядро.тести import обвязка as о

ДЖЕРЕЛА = os.path.join(о.КОРІНЬ, "джерела")


def картки(в):
    return [Картка.з_json(к) for к in в["картки"]]


class Ш_Протокол(unittest.TestCase):
    def setUp(self):
        """Перевіряє спільний транспорт окремо від предметних частин."""
        підміна = patch.object(руки, "рука", о.рука_транспорту)
        підміна.start()
        self.addCleanup(підміна.stop)

    def test_наскрізна_нитка_с5(self):
        """с5:6 → вибір с5:12 → опис с5:19: чотири картки одним повідомленням, кожна — з образу з вироком."""
        в, журнал = о.прогнати(протокол, о.вхід_с5(), о.записаний(о.тексти_с5()))
        кк = картки(в)
        self.assertEqual(sorted(к.рука for к in кк), [1, 2, 3, 4])
        self.assertTrue(all(к.збій is None and к.образ == "o6" and к.вирок for к in кк), в["картки"])
        self.assertEqual(sorted(к.позиція for к in кк), [0, 1, 2, 3])
        self.assertEqual([len(вв["картки"]) for вв in журнал["відповіді"]].count(0), len(журнал["відповіді"]) - 1)
        self.assertEqual(len(кк[0].речі), 4)
        self.assertTrue(кк[0].опис_en)
        self.assertEqual(в["заглушки"]["руки"], "Н3")
        self.assertEqual({з["вид"] for з in журнал["запити"]}, {"складання", "вибір", "опис"})

    def test_зупинка_лише_зі_збоєм(self):
        """Т33: модель руки 2 мовчить довше межі → `Збій{тиша, секунди}`; інші руки дають картки, усі разом."""
        в, журнал = о.прогнати(протокол, о.вхід_с5(), о.записаний(о.тексти_с5(), мовчить=(2,)))
        кк = {к.рука: к for к in картки(в)}
        self.assertEqual(sorted(кк), [1, 2, 3, 4])
        self.assertEqual((кк[2].збій.вид, кк[2].збій.секунди), ("тиша", о.МЕЖА_ТИШІ_С))
        self.assertTrue(all(кк[р].збій is None and кк[р].образ for р in (1, 3, 4)))
        self.assertTrue(all(not вв["картки"] for вв in журнал["відповіді"][:-1]))

    def test_зупинка_лише_зі_збоєм_зіпсована_відповідь(self):
        """Відповідь не за формою чи виняток частини — теж `Збій` на картці руки, а не зависання."""
        тексти = dict(о.тексти_с5(), вибір="не json")
        в, _ = о.прогнати(протокол, о.вхід_с5(), о.записаний(тексти))
        self.assertTrue(all(к.збій is not None and к.збій.частина == "розбір" for к in картки(в)))

    @unittest.skipUnless(os.path.isfile(os.path.join(os.environ.get("PYODIDE", "/нема"), "pyodide.js")),
                         "нема кеша Pyodide у $PYODIDE (CI ставить `стенд_pyodide_кеш.sh`)")
    def test_той_самий_вихід_cpython_і_pyodide(self):
        """Т34: та сама нитка с5 у CPython і в Pyodide дає однакові картки й запити."""
        тут = json.dumps(self._нитка(), ensure_ascii=False, sort_keys=True)
        там = subprocess.run(["node", os.path.join(ДЖЕРЕЛА, "ядро", "тести", "pyodide_нитка.js"),
                              os.environ["PYODIDE"], ДЖЕРЕЛА], capture_output=True, text=True, timeout=600)
        self.assertEqual(там.returncode, 0, там.stderr[-2000:])
        self.assertEqual(json.dumps(json.loads(там.stdout.strip().splitlines()[-1]), ensure_ascii=False,
                                    sort_keys=True), тут)

    def _нитка(self):
        return о.нитка_транспорту()

    def test_версія_ситуації_на_кожному_виході(self):
        """Т35: вона змінила сценарій, поки збирались руки (16729): картки старої версії відкинуто з заявою."""
        # Своя розмова: версія 2 у розмові «с5» зробила б застарілими нитки інших тестів того самого процесу.
        стара = о.почати(протокол, о.вхід_с5(розмова="с5-т35", версія=1))
        нова = о.почати(протокол, о.вхід_с5(розмова="с5-т35", версія=2))
        в1, _ = о.довезти(протокол, стара, о.записаний(о.тексти_с5()))
        self.assertEqual(в1["картки"], [])
        self.assertIn({"заява": "застаріла_версія", "версія_ситуації": 1, "поточна": 2}, в1["звіт"])
        в2, ж2 = о.довезти(протокол, нова, о.записаний(о.тексти_с5()))
        self.assertTrue(в2["картки"] and all(к["версія_ситуації"] == 2 for к in в2["картки"]))
        self.assertTrue(all(з["версія_ситуації"] == 2 for з in ж2["запити"]))
        for кл, д in ((Пул, {"рука": 1, "сід": 1}), (Вирок, {"образ": "o1"}), (Картка, {"рука": 1}),
                      (Запит, {"ключ": "к", "рука": 1, "вид": "опис", "сід": 1})):
            with self.subTest(поняття=кл.__name__), self.assertRaises(ХибнеЗначення):
                кл.з_json(dict(д, версія_ситуації=0))

    def test_той_самий_вхід_той_самий_вихід(self):
        """Т47: с5 двічі в одному процесі й раз у свіжому — ті самі запити (пул і вирок у них) і картки."""
        перший, другий = self._нитка(), self._нитка()
        свіжий = subprocess.run([sys.executable, "-c",
                                 "import json; from ядро.тести.тест_ш_протокол import Ш_Протокол as Ш; "
                                 "print(json.dumps(Ш()._нитка(), ensure_ascii=False))"],
                                cwd=ДЖЕРЕЛА, capture_output=True, text=True, timeout=300)
        self.assertEqual(свіжий.returncode, 0, свіжий.stderr[-2000:])
        self.assertEqual(перший, другий)
        self.assertEqual(json.loads(свіжий.stdout), перший)

    def test_режими_перемикачів_рук_на_ядрі(self):
        """Т49: кожен режим перемикачів рук іде шляхом ядра й дає картки; невідомий режим — `Збій`, не старий шлях."""
        for вибір, запис, частин in itertools.product(("list", "assess", "tournament"), ("повний", "короткий"),
                                                      (1, 2, 3)):
            with self.subTest(вибір=вибір, запис=запис, частин=частин):
                пм = {"вибір": вибір, "запис": запис, "частин": частин}
                в, журнал = о.прогнати(протокол, о.вхід_с5(перемикачі=пм), о.записаний(о.тексти_с5()))
                self.assertEqual(len(картки(в)), 4)
                self.assertTrue(all(з["перемикачі"] == пм for з in журнал["запити"]))
        в = о.почати(протокол, о.вхід_с5(перемикачі={"вибір": "навмання"}))
        self.assertTrue(в["кінець"])
        self.assertEqual((в["збій"]["вид"], в["збій"]["поле"]), ("перемикач", "вибір"))


if __name__ == "__main__":
    unittest.main()
