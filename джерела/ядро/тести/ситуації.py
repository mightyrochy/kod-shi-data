def прогнати(репліки, відповіді, попередня=None, дата=ДАТА, модель=None):
    """Один хід Ч1: репліки розмови й черга відповідей моделі → (Ситуація, Збій, запити, які ядро просило)."""
    г = ч1.хід({"репліки": репліки, "ситуація": попередня.в_json() if попередня else None, "дата": дата,
                "модель": модель})
    запити, черга = [], list(відповіді)
    try:
        з = next(г)
        while True:
            запити.append(з)
            з = г.send(черга.pop(0))
    except StopIteration as кінець:
        с, збій = кінець.value
    return с, збій, запити


def ситуація(сцена, ходів=None, дата=ДАТА):
    """Ситуація сцени після її ходів зі складеними відповідями."""
    с, репліки = None, []
    for слова, відповідь in СЦЕНИ[сцена][:ходів]:
        репліки.append({"хто": "вона", "текст": слова})
        с, збій, _ = прогнати(репліки, [{"текст": відповідь}], с, дата)
        assert збій is None, збій
        репліки.append({"хто": "стилістка", "текст": "Записала."})
    return с
