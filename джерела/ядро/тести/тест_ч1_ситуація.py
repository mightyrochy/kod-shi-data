"""Ч1 · Н1: Т1 — `Ситуація` відкидає чужий ключ (`РЕЗУЛЬТАТ.md`, §4)."""
import unittest

from ядро.поняття import Ситуація, ЧужийКлюч, ХибнеЗначення, НЕВІДОМО


class Ч1_Ситуація(unittest.TestCase):
    def test_ситуація_відкидає_чужий_ключ(self):
        """Т1: нове поле без опису — помилка конструктора з назвою ключа, запис не губиться мовчки (дошка 16262)."""
        for д, ключ in (({"версія": 1, "погода_вчора": 1}, "погода_вчора"),
                        ({"версія": 1, "сказала": {"дорога_пішки": {"значення": 20}}}, "дорога_пішки"),
                        ({"версія": 1, "сказала": {"етапи": [{"уривок": "потім ресторан", "година": "19:00"}]}},
                         "година"),
                        ({"версія": 1, "виведено": {"смуга_погоди": {"значення": "warm"}}}, "смуга_погоди")):
            with self.subTest(ключ=ключ):
                with self.assertRaises(ЧужийКлюч) as к:
                    Ситуація.з_json(д)
                self.assertEqual(к.exception.ключ, ключ)
                self.assertIn(ключ, str(к.exception))

    def test_невідомо_окреме_значення_і_джерела_блоків(self):
        """Не сказане — «невідомо», а не None чи []; виведене не має джерела її слів, її слово — без уривка нема."""
        с = Ситуація.з_json({"версія": 2, "сказала": {"місяць": {"значення": 8, "джерело": "її_слова",
                                                                  "уривок": "в серпні"}}})
        self.assertEqual(с.сказала["смуга_погоди"].значення, НЕВІДОМО)
        self.assertEqual(с.сказала["етапи"], НЕВІДОМО)
        self.assertEqual(с.в_json()["сказала"]["місяць"]["уривок"], "в серпні")
        self.assertEqual(Ситуація.з_json(с.в_json()), с)
        for д in ({"версія": 1, "виведено": {"пора_року": {"значення": "summer", "джерело": "її_слова",
                                                          "уривок": "в серпні"}}},
                  {"версія": 1, "сказала": {"подія": {"значення": "wedding", "джерело": "її_слова"}}},
                  {"версія": 1, "сказала": {"подія": {"значення": "wedding", "джерело": "типове"}}},
                  {"версія": 0}):
            with self.subTest(д=д), self.assertRaises(ХибнеЗначення):
                Ситуація.з_json(д)


if __name__ == "__main__":
    unittest.main()
