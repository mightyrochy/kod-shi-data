def _облік(кандидати):
    """Зіставляє id між моделлю й каталогом."""
    return {р["ід"]: р["н"] for р in кандидати.речі}


def _відповідь(**поля):
    """Робить дротову відповідь без виклику моделі."""
    return {"текст": json.dumps({"version": "1", **поля}, ensure_ascii=False)}


def _збір(кандидати, *ід):
    """Будує відповідь складання з адрес пулу."""
    адреси = _облік(кандидати)
    return _відповідь(outfits=[{"id": "o1", "items": [адреси[і] for і in ід]}])


def _опис(образ, **поля):
    """Будує повне пояснення із структурованим переліком речей."""
    return _відповідь(text="This outfit fits the occasion.",
                     about_items=[{"n": р["н"], "text": "A known item."} for р in образ.речі], **поля)


