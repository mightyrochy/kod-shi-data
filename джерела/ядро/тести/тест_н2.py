        тіло, рядки = self._перший_запит(каталог, портрет={"шкіра": ["#dbab95"], "очі": "#625448"})
        self.assertEqual(тіло["person"]["palette"], "unknown")
        рядок, = рядки
        self.assertEqual(рядок["palette_branch"], "unknown")
        self.assertEqual(рядок["L"], 42)
        self.assertIn("break", тіло["poles_unavailable"])

        from ядро.перекладач_паспорта import підготувати_портрет_і_палітру
