def _запис(ід, слот, **поля):
    """Синтетичний рядок із відомою ціною."""
    return {"id": ід, "слот": слот, "назва": ід, "ціна": 1200, **поля}


def _складений_каталог():
    """Речі для двох складів і заміни тієї самої пари."""
    return [_запис("dress", "сукня", тип="сукня", формальність=7, колір_ім="білий", фото=["https://example.com/a"]),
            _запис("boots", "взуття", каблук_см=4, формальність=5, фото=["https://example.com/b"]),
            _запис("sandals", "взуття"), _запис("bag", "сумка"), _запис("belt", "пояс")]


def _облік(кандидати):
    """Зіставляє id між моделлю й каталогом."""
    return {р["ід"]: р["н"] for р in кандидати.речі}


def _відповідь(**поля):
    """Робить дротову відповідь без виклику моделі."""
    return {"текст": json.dumps({"version": "1", **поля}, ensure_ascii=False)}


def _збір(кандидати, *ід):
    """Будує відповідь складання з адрес пулу."""
    адреси = _облік(кандидати)
    return _відповідь(outfits=[{"id": "o1", "items": [адреси[і] for і in ід]}])


def _опис(образ, **поля):
    """Будує повне пояснення із структурованим переліком речей."""
    return _відповідь(text="This outfit fits the occasion.",
                     about_items=[{"n": р["н"], "text": "A known item."} for р in образ.речі], **поля)


class ПалітраУШтатномуЗапуску(TestCase):
    def _перший_запит(self, каталог, *, намір="conventional", схема=None, портрет=None):
        профіль = {"колір": (портрет if портрет is not None else
                             {"шкіра": ["#dbab95"], "волосся": ["#473227"], "очі": "#625448"}),
                   "палітра": {"схема": схема},
                   "сценарій": {"нагода": "everyday", "місце": "park"}}
        вхід = обвязка.вхід_с5(розмова="фікстура палітри", каталог=каталог,
                               профіль=профіль, паспорт={"намір": намір})
        результат = обвязка.почати(протокол, вхід)
        self.assertIsNone(результат.get("збій"), результат)
        self.addCleanup(протокол._СЕСІЇ.pop, результат["сесія"], None)
        запитання, = результат["запити"]
        тіло = json.loads(запитання["модель"]["messages"][0]["content"])
        рядки = [dict(zip(тіло["pool"]["cols"], рядок)) for рядок in тіло["pool"]["rows"]]
        return тіло, рядки

    def test_спільна_палітра_й_запасна_хвиля_в_першому_запиті(self):
        """Слот без основного влучання отримує кандидата саме з запасної хвилі."""
        каталог = [_запис("backup", "сукня", тип="сукня", lab=(8, -16, 12),
                          колір_тип="вимір", колір_джерело="фото")]
        тіло, рядки = self._перший_запит(каталог)
        колір = тіло["person"]["palette"]
        self.assertEqual(колір["source"], "код")
        self.assertTrue(колір["value"]["default_branch"])
        self.assertEqual({х["wave"] for х in колір["value"]["window_waves"]}, {0, 1})
        рядок, = рядки
        self.assertEqual(рядок["palette_branch"], "ядро")
        self.assertEqual(рядок["rank_facts"]["wave"], 1)
        self.assertIn("break", тіло["poles_unavailable"])

    def test_обрана_схема_і_розрив_у_першому_запиті(self):
        """Гілки й полюс походять із видимих кандидатів, понад підлогу слота."""
        слоти = {"низ": "спідниця", "взуття": "туфлі", "верх": "блуза", "сукня": "сукня"}
        точки = [(L, a, b) for L in (18, 32, 45, 59, 75, 88)
                 for a, b in ((0, 0), (7, -3), (10, 15), (-16, 22), (30, 25), (18, -30), (-31, -8))]
        каталог = [_запис(f"{слот}-{і:02}", слот, тип=тип, lab=lab, колір_тип="вимір", колір_джерело="фото")
                   for слот, тип in слоти.items() for і, lab in enumerate(точки)]
        тіло, рядки = self._перший_запит(каталог, намір="statement", схема="аналогова")
        колір = тіло["person"]["palette"]["value"]
        self.assertEqual(колір["scheme"], "аналогова")
        self.assertFalse(колір["default_branch"])
        кількість = Counter(р["kind"] for р in рядки)
        self.assertEqual(set(кількість), {"top", "bottom", "dress", "shoes"})
        self.assertTrue(all(20 < n <= len(точки) for n in кількість.values()))
        self.assertEqual({р["kind"] for р in рядки if р["rank_facts"].get("primary_break")}, {"shoes"})
        self.assertIn("break", {п["id"] for п in тіло["poles"]})

    def test_без_волосся_немає_обчислених_вікон(self):
        """Шкіра не підставляється замість відсутнього волосся; колір речі лишається відомим."""
