    def test_тріада_в_чеклісті_вироку(self):
        """Т44: за відомої основи й кольору суд міряє тріаду, за відсутнього портрета називає поле."""
        день = ситуації.ситуація("с5")
        день = ситуація.тап(день, "схема", "triad", ситуації.ДАТА)
        каталог = [_запис(ід, слот, lab=[50, 0, 0], колір_тип="вимір", колір_джерело="фото")
                   for ід, слот in (("coat", "верхній_шар"), ("dress", "сукня"), ("shoes", "взуття"))]
        профіль = {"колір": {"шкіра": "#dbab95", "волосся": "#473227", "очі": "#625448"},
                   "палітра": {"вибір_кольору": {"база": "red", "база_hex": "#a82035", "база_тип": "колір"}}}
        for вхід in ({}, {"профіль": профіль}):
            with self.subTest(портрет=bool(вхід)):
                риси, план = знання.портрет_і_палітра(вхід, день)
                с = ситуація.з_профілем(день, план, риси)
                кандидати = пул.зібрати(с, 1, 3, каталог)
                образ, = розбір.прочитати(_збір(кандидати, "coat", "dress", "shoes"), "складання", кандидати)
                вирок = суд.судити(образ, с, кандидати, {})
                self.assertNotIsInstance(вирок, Збій)
                стан = вирок.чекліст["K-COL-03"]
                опис = розбір.прочитати(_опис(образ), "опис", кандидати, образ=образ)
                к = картка.зібрати(образ, вирок, опис, кандидати, (), ситуація=с)
                if вхід:
                    self.assertEqual(план["дані"]["scheme"], "тріада")
                    self.assertEqual(стан["стан"], "суджено")
                    self.assertTrue(any(з["правило"] == "K-COL-03" for з in к.заяви_картки))
                    self.assertIsNone(к.дія_для_вибору)
                else:
                    self.assertEqual(стан, {"стан": "немає_входу", "поле": "профіль.колір"})
                    заява, = к.дія_для_вибору["statements"]
                    self.assertEqual(заява["values"], {"scheme": "triad", "action": "add_portrait"})
                    self.assertFalse(any(з.get("поле") == "профіль.колір" for з in к.невідоме))

        давня_схема = Ситуація(1, {"схема": Факт("нема_такої", "форма")})
        _, план = знання.портрет_і_палітра({"профіль": профіль}, давня_схема)
        self.assertEqual(план["дані"]["unknown_scheme"], "нема_такої")
        self.assertEqual(план["вибір_схеми"]["обрала"]["scheme"], "code_rank")

    def test_сміливе_доходить_до_вибору(self):
        """Т45: модель бачить зауваження до сміливого образу і все одно може обрати його."""
        день = Ситуація(1, {"намір": (Факт("statement", "форма"),)})
        каталог = [*_складений_каталог(), _запис("bold", "сукня", тип="сукня", візерунок="леопард")]
        вхід = обвязка.вхід_с5(каталог=каталог, ситуація=день.в_json())
        відбиток_сміливого = []

        def модель(запит):
            if запит["рука"] != 1:
                return _складач(запит)
            тіло = json.loads(запит["модель"]["messages"][0]["content"])
            if запит["вид"] == "складання":
                кандидати = пул.зібрати(день, 1, вхід["сід"], каталог)
                self.assertGreater(кандидати.сміливих, 0)
                іди = {р["ід"]: р["н"] for р in кандидати.речі}
                склади = [{"id": і, "items": [іди[сукня], іди["boots"]]}
                          for і, сукня in (("o1", "dress"), ("o2", "bold"))]
                відбиток_сміливого.extend(склади[1]["items"])
                return _відповідь(outfits=склади)
            if запит["вид"] == "вибір":
                сміливий, = (о for о in тіло["verdict"] if о["id"] == "o2")
                self.assertEqual(сміливий["items"], відбиток_сміливого)
                self.assertTrue(сміливий["findings"])
                return _відповідь(chosen="o2")
            return _складач(запит)

        справжні = знання.заяви

        def заяви(образ, *args, **kwargs):
            yield from справжні(образ, *args, **kwargs)
            if образ.рука == 1 and образ.номер == "o2":
                yield "K-COL-05", "accent_orphan", (образ.речі[0]["н"],), {
                    "факти": {}, "ремонт": None, "вага": 0.5, "регістр": "репліка"}

        with patch.object(знання, "заяви", заяви):
            вихід, _ = обвязка.прогнати(протокол, вхід, модель)
        к, = (к for к in вихід["картки"] if к["рука"] == 1)
        self.assertEqual((к["образ"], к["вирок"]), ("o2", "o2"))

