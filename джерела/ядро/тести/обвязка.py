"""Обв'язка тестів ядра: заглушка моделі й показ, що везе запити (`РЕЗУЛЬТАТ.md`, §3 «Записана чи складена відповідь»).

`прогнати(вхід, відповідач)` грає роль показу за протоколом «ядро просить — показ везе» (`ОПИС.md`, розділ 5):
«почати», далі на кожен запит — «відповідь» від відповідача, доки ядро не скаже «кінець». Відповідач — заглушка
моделі: `записаний` відтворює записану відповідь проходу через міст 20.11, `складений` приймає відповідь, складену
тестом. Обв'язка чиста: без годинника, мережі й випадковості, тож той самий вхід дає той самий вихід у CPython і
Pyodide (Т34, Т47). Мовчання моделі довше межі показ подає як збій «тиша» з секундами — так само, як збій мосту.
"""
import json
import os

КОРІНЬ = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
ЗАПИСИ = os.path.join(КОРІНЬ, "аудит", "проби", "Живий-через-міст", "стенд", "службове")
# с5, прохід 1: складання руки 1, вибір після ремонту, опис (рядки від нуля; `ОПИС.md`, розділ 1).
РЯДКИ_С5 = {"складання": 6, "вибір": 12, "опис": 19}
МЕЖА_ТИШІ_С = 300


def текст_запису(сцена, рядок):
    """Текст відповіді моделі з рядка `обміни.jsonl` (блок `text`, без думок)."""
    with open(os.path.join(ЗАПИСИ, сцена, "обміни.jsonl"), encoding="utf-8") as ф:
        запис = json.loads([р for р in ф if р.strip()][рядок])
    return "".join(б["text"] for б in json.loads(запис["відповідь"])["content"] if б["type"] == "text")


def тексти_с5():
    return {вид: текст_запису("с5_весілля_сестри", р) for вид, р in РЯДКИ_С5.items()}


def записаний(тексти, мовчить=()):
    """Заглушка моделі: на запит виду — записаний текст; рука з `мовчить` не відповідає довше межі."""
    def відповісти(запит):
        if запит["рука"] in мовчить:
            return {"збій": {"вид": "тиша", "секунди": МЕЖА_ТИШІ_С}}
        return {"текст": тексти[запит["вид"]]}
    return відповісти


def вхід_с5(**зміни):
    вхід = {"розмова": "с5", "версія": 1, "сід": 178637, "дата": "2026-08-01",
            "паспорт": {"сцена": "с5_весілля_сестри"}, "профіль": {},
            "перемикачі": {"вибір": "list", "запис": "повний", "частин": 1}}
    вхід.update(зміни)
    return вхід


def почати(протокол, вхід):
    return json.loads(протокол.виклик(json.dumps({"дія": "почати", "вхід": вхід}, ensure_ascii=False)))


def прогнати(протокол, вхід, відповідач, відповіді=None):
    """Показ без екрана: везе кожен запит, доки ядро не скаже «кінець». Вертає останню відповідь ядра і журнал."""
    в = почати(протокол, вхід)
    return довезти(протокол, в, відповідач)


def довезти(протокол, в, відповідач):
    журнал = {"запити": list(в.get("запити", [])), "відповіді": [в]}
    черга = list(в.get("запити", []))
    while not в.get("кінець"):
        if not черга:
            raise AssertionError("ядро не скінчило й не просить нічого: зупинка без збою")
        з = черга.pop(0)
        в = json.loads(протокол.виклик(json.dumps(
            {"дія": "відповідь", "сесія": в.get("сесія") or з["сесія"], "ключ": з["ключ"],
             "відповідь": відповідач(з)}, ensure_ascii=False)))
        черга += в.get("запити", [])
        журнал["запити"] += в.get("запити", [])
        журнал["відповіді"].append(в)
    return в, журнал
