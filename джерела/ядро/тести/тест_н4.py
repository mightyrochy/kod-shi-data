ЗАПИСИ = Path(__file__).resolve().parents[3] / "аудит" / "проби" / "Живий-через-міст" / "стенд" / "службове"
СЦЕНИ_ЗАПИСІВ = {"с5": "с5_весілля_сестри", "с6": "с6_ювілей_свекрухи", "ж3": "ж3_кафе_20"}


def запис(сцена, рядок):
    """Текст відповіді моделі з записаного обміну сцени."""
    рядки = (ЗАПИСИ / СЦЕНИ_ЗАПИСІВ[сцена] / "обміни.jsonl").read_text(encoding="utf-8").splitlines()
    відповідь = json.loads(json.loads(рядки[рядок])["відповідь"])
    return "".join(б.get("text", "") for б in відповідь["content"] if б.get("type") == "text")


def її(слова):
    return [{"хто": "вона", "текст": слова}]


def _пара(ід, **поля):
    return {"id": ід, "слот": "взуття", "назва": ід, "ціна": 1500, "тип": "черевики", **поля}


def _каталог(*пари):
    return [{"id": "сукня", "слот": "сукня", "назва": "сукня", "ціна": 2000, "тип": "сукня", "формальність": 5},
            *пари]


def тіло_руки1(с, каталог=None, розмова="н4"):
    """Тіло запиту руки 1, який ядро будує з цієї `Ситуації`."""
    вхід = обвязка.вхід_с5(розмова=розмова, каталог=каталог or _каталог(_пара("пара", каблук_см=2)))
    вхід["ситуація"] = с.в_json()
    в = обвязка.почати(протокол, вхід)
    протокол._СЕСІЇ.pop(в.get("сесія"), None)
    з = next(з for з in в["запити"] if з["рука"] == 1)
    return json.loads(з["модель"]["messages"][0]["content"])


def без_уривків(с):
    """`Ситуація` у JSON без уривків — те, що код записав сам."""
    def чисто(в):
        if isinstance(в, dict):
            return {к: чисто(з) for к, з in в.items() if к != "уривок"}
        if isinstance(в, list):
            return [чисто(з) for з in в]
        return в
    return json.dumps(чисто(с.в_json()), ensure_ascii=False)


