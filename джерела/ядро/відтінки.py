"""Колір речі в записі нового виду — коди відтінку від моделі зору з галереї (корінь `Річ-колір-вимір`, «Інваріант
ПІСЛЯ»; наряд `Запис-речі-колір-мітка`).

Словник — `дані/відтінки.json`: 267 блоків ISCC–NBS, кожен код — ділянка простору модуля кольору; точку (центроїд
блоку) і родину читачі беруть лише з ділянки коду, hex моделі не береться, пікселів код не міряє. Мітку «колір»
визначає `дані/мітки_речі.json` (перевірка — `мітки.py`), Річ із нею складає Ч2 (`річ.py`) через `факт` нижче.
"""
import json
from pathlib import Path

from .поняття import НЕ_ПЕВНИЙ, Факт

with Path(__file__).with_name("дані").joinpath("відтінки.json").open(encoding="utf-8") as _файл:
    ВІДТІНКИ = json.load(_файл)["відтінки"]

КОДИ = tuple(ВІДТІНКИ)
НАЙБІЛЬШЕ = 4


def групи():
    """Коди за родиною ISCC у порядку словника — для промпту запису."""
    вихід = {}
    for код, в in ВІДТІНКИ.items():
        вихід.setdefault(в["родина"], []).append(код)
    return вихід


def перевірити(відп, джерело):
    """Відповідь моделі `{в, принт, межі}` мітки «колір» → (значення мітки або None, збій або None).

    `в` — перелік `{код, частка}` (основний першим; один код рядком — частка 1), `принт` — так чи ні; модель вагається
    — `в` «не_певний» і `межі` з двома різними кодами. Код поза словником, частка поза (0; 1] чи сума часток понад 1 —
    збій: запис не вгадує за модель."""
    в = відп.get("в")
    if в == НЕ_ПЕВНИЙ:
        межі = відп.get("межі")
        if not isinstance(межі, list) or len(межі) != 2 or межі[0] == межі[1] or any(к not in ВІДТІНКИ for к in межі):
            return None, f"«не_певний» — два різні коди відтінку, а не {межі!r}"
        return {"значення": НЕ_ПЕВНИЙ, "джерело": джерело, "межі": list(межі)}, None
    if isinstance(в, str):
        в = [{"код": в, "частка": 1}]
    if not isinstance(в, list) or not в or len(в) > НАЙБІЛЬШЕ:
        return None, f"очікувано від 1 до {НАЙБІЛЬШЕ} кодів відтінку з частками, а не {в!r}"
    відтінки = []
    for пункт in в:
        код = пункт.get("код") if isinstance(пункт, dict) else None
        частка = пункт.get("частка") if isinstance(пункт, dict) else None
        if код not in ВІДТІНКИ or код in (к["код"] for к in відтінки):
            return None, f"код відтінку {код!r} поза словником чи двічі"
        if isinstance(частка, bool) or not isinstance(частка, (int, float)) or not 0 < частка <= 1:
            return None, f"частка {частка!r} поза (0; 1]"
        відтінки.append({"код": код, "частка": частка})
    if sum(к["частка"] for к in відтінки) > 1.05:
        return None, "сума часток понад 1"
    принт = відп.get("принт")
    if принт is not None and not isinstance(принт, bool):
        return None, f"принт — так чи ні, а не {принт!r}"
    вихід = {"значення": відтінки, "джерело": джерело}
    if принт is not None:
        вихід["принт"] = принт
    return вихід, None


def факт(мітка, слово_крамниці):
    """Перевірена мітка «колір» → Факт кольору Річ. Код — точка, hex, світлота й родина центроїда ділянки основного
    коду (родину рахує той самий модуль, що й для будь-якої точки, `колір_тон.сім_я_кольору`); «не певний» — обидва
    коди як межі, без точки; слово крамниці лишається при речі, але кольору не дає."""
    if мітка["значення"] == НЕ_ПЕВНИЙ:
        return Факт(НЕ_ПЕВНИЙ, мітка["джерело"], межі={"відтінки": tuple(мітка["межі"]),
                                                        "слово_крамниці": слово_крамниці})
    from колір_річ import lch
    from колір_тон import сім_я_кольору
    основний = мітка["значення"][0]["код"]
    ділянка = ВІДТІНКИ[основний]
    lab = tuple(ділянка["lab"])
    сімʼя = сім_я_кольору(lab)[0]
    значення = {"lab": lab, "hex": ділянка["hex"], "L": round(lch(lab)[0]), "family": сімʼя, "color": основний,
                "відтінки": tuple((к["код"], к["частка"]) for к in мітка["значення"])}
    if "принт" in мітка:  # модель не сказала — ключа нема: «ні» не вгадуємо
        значення["принт"] = мітка["принт"]
    значення["слово_крамниці"] = слово_крамниці
    return Факт(значення, мітка["джерело"])
