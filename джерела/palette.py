def _кулі_слотів(спец):
    """ОДИН список куль K-MUA-01 на слот — від УСІХ обраних рис разом.

    ЧОМУ НЕ НА РЯДКУ, ДЕ ВОНО СТОЯЛО. Вікна слота йдуть у фід диз'юнкцією
    («річ пройшла, якщо пройшла хоч один рядок»), а куля висіла рівно на тому
    рядку, який сама ж і породила — рядку макіяжу. Відколи поруч із ним стали
    рядки рис, персональної й практикової палітр, помада проходила в каталог
    сусіднім рядком того самого слота, не зустрівши жодної перевірки: анти-правило
    трималось не на слоті, а на випадковій одиничності рядка.
    Виключення — властивість СЛОТА («на цій площі цього кольору не буває»), тож
    і збирається воно на слот, а накладається на всі рядки слота разом."""
    тв = спец.get("тон_від_рис") or {}
    if not тв.get("придатно"): return {}
    кулі = {}
    for nm, дані in (тв.get("риси") or {}).items():
        for s in K_MUA_01_ПЛОЩА:
            к = _куля_макіяжу(дані, s)
            if к: кулі.setdefault(s, []).extend(к)
    return кулі


def _рядки_від_рис(спец):
    """Вікна каталогу від рис — ОКРЕМИМИ рядками поруч зі схемними, не замість.
    Той самий патерн, що вже стоїть для `принт_ехо` і «якір-нейтраль»: шар
    retrieval пробує обидва, порожнє одне з двох не означає порожній слот.

    L і C беруться з ГОТОВОГО вікна слота без змін — рядок відрізняється від
    схемного РІВНО дугою тону. Тому будь-яка різниця у видачі приписується осі
    тону, а не побічній зміні світлоти чи хроми."""
    тв = спец.get("тон_від_рис") or {}
    if not тв.get("придатно"): return []
    рядки = []
    for s, v in спец["слоти"].items():
        if "сім_я" in v: continue                  # нейтральний слот тону не несе
        if v.get("попередження"): continue         # вироджена роль: кольору там не буває
        for nm, дані in тв["риси"].items():
            for d in дані.get("дуги", []):
                lo, hi = d["дуга"]
                обрана = (дані.get("рід") == "обрана")
                r = dict(слот=s, L_min=v["L"][0], L_max=v["L"][1],
                         C_min=v["C"][0], C_max=v["C"][1],
                         h_from=lo, h_to=hi, нейтраль=False,
                         роль=v.get("роль"),
                         джерело_тону=("макіяж:%s" % дані.get("зона") if обрана
                                       else "риса:%s" % nm),
                         риса=nm, відношення=тв["відношення"], обрана=обрана,
                         тиск_центр=d["тиск_центр"], тиск_межі=d["тиск_межі"],
                         чому=(("дуга виведена з ОБРАНОГО кольору макіяжу «%s»: це "
                                "не вимір людини, а рішення, яке вона вже ухвалила "
                                "й яке саме може бути невдалим. Рядок знімається "
                                "окремо від рис, і його НЕ можна подавати з тією ж "
                                "силою, що дугу шкіри" % дані.get("зона"))
                               if обрана else
                               ("дуга виведена з ТОНУ РИСИ «%s», не з якоря-схеми; "
                                "риси не усереднюються — це окремий рядок на кожну"
                                % nm)))
                # перегук: та сама дуга підтримана ДРУГОЮ рисою — це сильніший рядок,
                # і він мусить бути видимий, бо саме він відрізняє «одна риса каже»
                # від «дві риси кажуть те саме»
                хто = [p["риси"] for p in тв["перегуки"] if nm in p["риси"]]
                if хто: r["перегук_з"] = sorted({x for p in хто for x in p if x != nm})
                напр = [p for p in тв["напруги"] if nm in p["риси"]]
                if напр: r["напруга_з"] = [dict(риси=p["риси"], суть=p["суть"]) for p in напр]
                # Куля K-MUA-01 тут БІЛЬШЕ НЕ СТАВИТЬСЯ: вона накладається на всі
                # рядки слота одним проходом у `запит_у_фід` (див. `_кулі_слотів`).
                рядки.append(r)
    # ── ПЕРЕГУК ЯК ОКРЕМЕ, ВУЖЧЕ ВІКНО ───────────────────────────────────────
    # Спільна дуга двох рис — не те саме, що дуга кожної з них: вона вужча й
    # спирається на дві незалежні риси. Без окремого рядка ця різниця зникала б
    # у диз'юнкції «пройшов хоч одне вікно».
    for p in тв["перегуки"]:
        for a in p["спільні_дуги"]:
            зн = тиск_знахідка((a[0] + (((a[1] - a[0]) % 360) / 2)) % 360, тв["h_шкіри"])
            for s, v in спец["слоти"].items():
                if "сім_я" in v or v.get("попередження"): continue
                # Перегук між ДАНОЮ рисою й ОБРАНИМ кольором макіяжу — теж обраний:
                # інакше помада проходила б у фід непідписаною, через задні двері
                # резонансу, поки прямий її рядок чесно марковано. Рівно та тиха
                # протічка, проти якої вся ця розмітка й заведена.
                обрана_п = any((тв["риси"].get(x) or {}).get("рід") == "обрана"
                               for x in p["риси"])
                рядки.append(dict(
                    слот=s, L_min=v["L"][0], L_max=v["L"][1],
                    C_min=v["C"][0], C_max=v["C"][1],
                    h_from=a[0], h_to=a[1], нейтраль=False, роль=v.get("роль"),
                    джерело_тону="перегук:%s" % "+".join(p["риси"]),
                    риси=list(p["риси"]), Δтемпература=p["Δтемпература"],
                    тиск_центр=(зн["сила_нп"] if зн else 0.0), обрана=обрана_п,
                    чому=("спільна дуга двох рис: вужча за кожну окремо і спирається "
                          "на дві риси, а не на одну"
                          + (". ⚠ одна з них — ОБРАНИЙ колір макіяжу, тож рядок "
                             "успадковує його рід і знімається разом із ним"
                             if обрана_п else ""))))
    return рядки


def запит_у_фід(спец):
    """Пласка форма під SQL/XML-фільтр: те, що реально піде в інджест каталогу.

    ДОДАНО: якщо специфікація несе принт, ехо-запит виходить ОКРЕМИМ рядком на той
    самий слот (а не перезаписує його базове вікно) — з полем `сила`, щоб шар
    retrieval міг спершу спробувати ехо, а тоді відступити до базового вікна.
    Без цього ехо жило в специфікації й не доходило до фіду."""
    запити = []
    for s, v in спец["слоти"].items():
        r = dict(слот=s, L_min=v["L"][0], L_max=v["L"][1], C_min=v["C"][0], C_max=v["C"][1],
                 h_from=(v.get("дуга_тону") or (None, None))[0],
                 h_to=(v.get("дуга_тону") or (None, None))[1],
                 нейтраль=("сім_я" in v), спроба=0)
        нт = v.get("нейтраль_темп")
        if нт:      # напрям B: температурне вікно нейтралі доходить до фільтра каталогу
            r["b_min"], r["b_max"] = нт["b_min"], нт["b_max"]
            r["температура_сила"] = нт["сила_переваги"]
        запити.append(r)
    for s, v in спец["слоти"].items():
        q = v.get("принт_ехо")
        if q:
            # `спроба=1`: ехо — це ЗАПАСНЕ вікно поруч із базовим («шар retrieval міг
            # спершу спробувати ехо, а тоді відступити»), а не другий рівноправний
            # рядок. Досі пріоритет жив у коментарі й у полі `сила`, якого ніхто не
            # читав як черговість, — тепер він стоїть у рядку числом.
            запити.append(dict(q, слот=s, спроба=1))
    # ── ЯКІРНІ СЛОТИ МУСЯТЬ МАТИ ЩЕ Й НЕЙТРАЛЬНЕ ВІКНО ──────────────────────
    # ЗНАЙДЕНО НАСКРІЗНИМ ПРОГОНОМ НА РЕАЛІСТИЧНОМУ КАТАЛОЗІ, і жодним шаровим
    # стендом: жодне взуття не проходило ЖОДНОГО вікна. Причина — усі чотири схеми
    # давали для «взуття» вікно з `нейтраль=False` і `C_min ≥ 14`, бо роль слота
    # «секундант», тобто кольоронесуча.
    # У реальному каталозі взуття, сумки й пояси — переважно НЕЙТРАЛІ: чорний,
    # бежевий, нюд, коричневий, білий. Виміряно на фікстурі: чорний C*4.4,
    # бежевий C*17.5 при h 76 — жоден не влучає у вимогу хроми з дугою тону.
    # Наслідок був тихий і повний: `feed.покриття` звітував «порожньо» на кожному
    # взуттєвому вікні, композитор відступав до «перших N без колірного критерію»,
    # і колірний шар на цьому слоті не працював ЗОВСІМ — на будь-якому фіді.
    #
    # ⚠ ЦЕ НЕ СКАСОВУЄ кольорового вікна: кольорове взуття існує й лишається
    # придатним. Додається ДРУГИЙ рядок, а не заміна — так само, як зроблено для
    # `принт_ехо` вище. Шар retrieval пробує обидва; порожнє одне з двох більше не
    # означає порожній слот.
    # Температурне вікно нейтралі (b*) береться те саме, що вже порахувала
    # `нейтраль_якір` у `специфікація` (поле `якір_нейтраль_темп`), тож нового
    # знання тут нема — лише доставка наявного туди, де його бракувало.
    # ⚠ ДОТИ ЦЕЙ КОМЕНТАР ОПИСУВАВ МЕХАНІЗМ, ЯКОГО НЕ БУЛО: рядок читав
    # `нейтраль_темп`, яке ставиться лише СХЕМНО-нейтральному слотові, а якірний
    # рядок додається саме тому, що слот схемно КОЛЬОРОВИЙ. Гілка була недосяжна
    # за побудовою — 0 із 456 рядків (Н-palette-2-099).
    for s, v in спец["слоти"].items():
        if s not in ЯКІРНІ_СЛОТИ: continue
        якщо_вже = any(q.get("слот") == s and q.get("нейтраль") for q in запити)
        if якщо_вже: continue
        нт = v.get("якір_нейтраль_темп") or {}
        # ── СВІТЛОТА ЯКІРНОЇ НЕЙТРАЛІ НЕ ОБМЕЖУЄТЬСЯ СМУГОЮ СХЕМИ ────────────
        # Друга проба показала, що самого нейтрального вікна МАЛО: з `L_min/L_max`
        # схеми (51–66) чорний черевик (L*10) і бежевий човник (L*71) далі не
        # проходили, і слот лишався порожнім.
        # Причина концептуальна, не арифметична. Смуга світлоти схеми — це план
        # КОЛІРНОЇ РОЛІ (секундант тримає середню світлоту). Для якірної нейтралі
        # ролі «секундант» нема: чорний човник працює і зі світлим, і з темним низом.
        # Те, що справді обмежує світлоту взуття, — КРОК СВІТЛОТИ до сусідньої речі
        # (K-COL-01) і когерентність нейтралей (K-CLR-02), а вони перевіряються на
        # ЗІБРАНОМУ образі, а не при доборі.
        # Отже смуга схеми тут ДУБЛЮВАЛА нижчий за течією гейт СТРОГІШОЮ й ІНШОЮ
        # умовою — і ціною цього був порожній слот на будь-якому фіді.
        # Вікно добору лишає температурне обмеження (воно про людину) і знімає
        # світлотне (воно про образ, і його перевіряють там, де образ уже є).
        r = dict(слот=s, L_min=0.0, L_max=100.0,
                 C_min=0.0, C_max=НЕЙТРАЛЬ_C_СТЕЛЯ,
                 h_from=None, h_to=None, нейтраль=True,
                 роль="якір-нейтраль",
                 # ── ЗАПАСНИЙ, А НЕ РІВНОПРАВНИЙ (Н-palette-2-098) ────────────
                 # Вікно L 0–100 × C 0–24 × будь-який тон у диз'юнкції «пройшов хоч
                 # один рядок» пропускало 97 % слота «взуття»/«сумка»: колірний шар
                 # на слотах-якорях ставав порожнім твердженням «підходить усе».
                 # Рядок додали проти ПОРОЖНЬОГО слота, і саме цю роль він і має
                 # виконувати — запасну. `спроба=1` каже це споживачеві числом:
                 # `feed.покриття` і `composer` беруть його ЛИШЕ там, де основна
                 # хвиля не дала жодного кандидата.
                 спроба=1,
                 L_не_обмежено="крок світлоти (K-COL-01) і когерентність нейтралей "
                               "(K-CLR-02) перевіряються на ЗІБРАНОМУ образі; "
                               "дублювати їх строгішою смугою при доборі означає "
                               "спорожнити слот",
                 чому="слот «%s» у реальному каталозі переважно нейтральний; "
                      "кольорове вікно лишається окремим рядком" % s)
        if нт.get("b_min") is not None:
            r["b_min"], r["b_max"] = нт["b_min"], нт["b_max"]
            r["температура_сила"] = нт.get("сила_переваги")
        запити.append(r)
    # ── ТОН ВІД ЛЮДИНИ (крок 1 задачі 42) ───────────────────────────────────
    # Рядки додаються ПОРУЧ зі схемними, а не замість: це дві різні осі («тон від
    # речі-якоря» і «тон від риси»), і зводити їх в одне вікно означало б знову
    # усереднити те, що корпус вимагає тримати окремо.
    # Тут стояло читання однойменного ключа зі спец як «кеш, якщо хтось порахував
    # раніше». Ніхто ніколи не рахував: аудит контрактів назвав це полем-сиротою
    # (читається, не пишеться ніде). Обіцянка кешу без записувача — не оптимізація,
    # а зайва гілка, що вдає, ніби вище по течії щось є. Виклик один, кеш зайвий.
    # (Імʼя ключа в коментарі НЕ відтворюється дослівно: сканер контрактів читає
    #  текст модуля, і згадка виразу воскресила б сироту, яку правка щойно зняла.)
    import personal_palette as _PP
    for r in _рядки_від_рис(спец):
        # ранг риси — ПОРЯДОК за Perrett 2023 (очі > волосся ≈ шкіра), макіяж завжди останній
        рід = _PP.рід_риси(r.get("риса") or "") if r.get("риса") else None
        r["ранг_риси"] = _PP.РАНГ_РИС.get(рід, 9) if рід else (
            min((_PP.РАНГ_РИС.get(_PP.рід_риси(x) or "", 9) for x in (r.get("риси") or [])), default=9))
        запити.append(r)
    # ── РЯДКИ З ПЕРСОНАЛЬНОЇ ПАЛІТРИ (24.08.2026) ────────────────────────────
    # Нейтралі від волосся/шкіри з b*-вікном і смугою світлоти ЛЮДИНИ; акценти від
    # очей. Це перші рядки, у яких L і C йдуть від людини, а не від схеми.
    for r in _PP.рядки_у_фід(спец):
        запити.append(r)
    # ── РЯДКИ З ПРАКТИКОВОЇ ПАЛІТРИ: сім'ї у версії людини (ранг 1 — сім'я очей) і
    # нейтралі за температурою палітри
    import palettes as _PL
    for r in _PL.рядки_у_фід(спец):
        запити.append(r)
    # ── K-MUA-01 НА ВЕСЬ СЛОТ, А НЕ НА ОДИН РЯДОК ────────────────────────────
    # Прохід стоїть ПІСЛЯ того, як зібрані ВСІ рядки (схемні, ехо, якірні, від рис,
    # з персональної та практикової палітр): вікна слота — диз'юнкція, тож дірка,
    # поставлена на одному рядку, витікає через сусідній.
    # НЕЙТРАЛЬНІ РЯДКИ ТЕЖ ДІСТАЮТЬ КУЛЮ, і це відхилення від початкового плану
    # правки, зроблене ВИМІРОМ, а не смаком. План казав нейтральні пропустити, бо
    # «нейтраль(lab) і так відсіює хроматичну помаду». На приймальному кольорі
    # #a9736b (C*24.1 при стелі нейтралі 24.0) це неправда: помада стоїть РІВНО на
    # межі коридору теплої нейтралі, і 17 точок дірки проходили саме нейтральними
    # рядками «верх» від персональної та практикової палітр. Приглушена помада —
    # не рідкість, тож виняток лишав дірку напіввідчиненою рівно для того класу
    # кольорів, проти якого правило й стоїть.
    # Для насиченої помади куля на нейтральному рядку інертна (жодна нейтраль не
    # лежить ближче за ΔE00 5 до хроматичного кольору) — отже це строго сильніше,
    # а не ширше.
    кулі_слота = _кулі_слотів(спец)
    if кулі_слота:
        for r in запити:
            кулі = кулі_слота.get(r.get("слот"))
            if кулі: r.setdefault("не_ближче_за", []).extend(кулі)
    # ── ЧЕРГА СПРОБ — ПОЛЕ РЯДКА, А НЕ ЗНАННЯ СПОЖИВАЧА ─────────────────────
    # Рядки від рис, з персональної та практикової палітр — усі основні (спроба 0).
    # Запасні лише два види, і вони позначені там, де народжуються: якірна нейтраль
    # і принт-ехо. Дефолт стоїть тут, щоб жоден рядок не пішов у фід без черги.
    for r in запити:
        r.setdefault("спроба", 0)
    # Стабільне сортування: рядки з рангом риси — за рангом; рядки без рангу (схемні,
    # якірні) лишаються попереду у своєму порядку. Черга рядків = черга спроб retrieval.
    запити.sort(key=lambda q: q.get("ранг_риси", 0) if isinstance(q, dict) else 0)
    return запити


# ─── B. НЕЙТРАЛЬ-ЯКІР ЗА ТЕМПЕРАТУРОЮ ОСОБИ (неперервно, без класів) ───────────
# Вісь температури нейтралі — b* (жовтий/синій), НЕ тон: при малій хромі h стрибає
# (чорний дав h=296.8, що зробило б його «синім»). Виміряні якорі в цьому ж просторі:
