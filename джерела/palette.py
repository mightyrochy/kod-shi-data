    # ── ОБРАНА ОСНОВА: ВІКНО ЇЇ СІМ'Ї, А НЕ РЕЧЕННЯ В ПАКЕТІ (19.09.2026) ─────
    # ЩО БУЛО (спостереження власника 19.09, `проби/kolir_akcent.py`): жінка обрала
    # основу «червоний (теплий)» і схему «нейтрали+акцент», а в пакет поїхали
