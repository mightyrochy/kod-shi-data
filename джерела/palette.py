# ─── світлотні поверхи ────────────────────────────────────────────────────────
def поверхи(особа, слоти, схема, сторона="темніша"):
    """Розкладка L* по ролях. Головне обмеження — асиметричне:
    біля обличчя вікно вузьке (K-CLR-02), а кроки світлоти (K-COL-01) мусять
    десь бути. Отже кроки йдуть у низ і взуття — і це не хитрість, а те саме,
    що корпус каже прямо: «низ і взуття майже вільні».

    `сторона` — з якого боку від шкіри стоїть річ біля обличчя. Раніше було
    зашито «темніша», хоч `outfit.цільове_вікно` прямо каже, що легітимні обидві.
    ВАЖЛИВО, ЩО ЦЕ ПАРАМЕТР САМЕ ТУТ, А НЕ НИЖЧЕ ПО ТЕЧІЇ: від приобличчевого
    вікна рахується вся драбина світлоти (секундант, акцент, низ). Перша версія
    правки міняла сторону в `поле_слота`, тобто ПІСЛЯ того, як драбина вже
    побудована від старої бази, — і виміряно вийшло: обличчя [40,67], акцент
    [41,56], тобто акцент цілком усередині приобличчевого вікна й кроку світлоти
    між ними нема ЗОВСІМ. Правка лікувала виродження і тихо ламала K-COL-01."""
    L_шк = особа["L_шкіри"]; gap = особа["value_gap"]
    темне = O.цільове_вікно(L_шк, gap, темніша=True)
    світле = O.цільове_вікно(L_шк, gap, темніша=False)
    вікно_обличчя = світле if сторона == "світліша" else темне
    if вікно_обличчя[1] - вікно_обличчя[0] < 6:      # особа з екстремальним контрастом
        вікно_обличчя = [max(0, вікно_обличчя[0]-6), min(100, вікно_обличчя[1]+6)]
    база = sum(вікно_обличчя)/2
    низ_вниз = [max(2, round(база - 2*КРОК - 8)), max(8, round(база - КРОК))]
    низ_вгору = [min(92, round(база + КРОК)), min(98, round(база + 2*КРОК + 8))]
    # низ веде в той бік, де більше місця в шкалі
    низ = низ_вниз if (база - 0) > (100 - база) else низ_вгору
    # Ролі далеко від обличчя мусять мати РІЗНІ поверхи, інакше буквальне виконання
    # специфікації дає низ, взуття й сумку на одній світлоті (побачено на циклі):
    # формально 2 кроки, фактично секундант і акцент нерозрізнимі.
    ширина = низ[1] - низ[0]
    секундант = [низ[0], round(низ[0] + ширина*0.45)]
    акцент = [round(низ[0] + ширина*0.55 + КРОК*0.5), min(96, низ[1] + round(КРОК))]
    return dict(біля_обличчя=вікно_обличчя, світле_біля_обличчя=світле,
                темне_біля_обличчя=темне, сторона=сторона,
                далеко_від_обличчя=низ, секундант_L=секундант, акцент_L=акцент,
                примітка="кроки світлоти виносяться від обличчя: біля лиця вікно задає "
                         "контраст особи, і рухати його не можна без штрафу K-CLR-02")

НОСІЇ_АКЦЕНТУ = ("сумка", "взуття", "шарф", "прикраси", "пояс", "головний_убір")

def розподіл_ролей(слоти, S, фокус=None):
    """ЗНАЙДЕНО ЗАМКНЕНИМ ЦИКЛОМ: схема оголошувала відлуння, а специфікація давала
    рівно один акцентний слот — і outfit.py блокував такий образ як «сирота-акцент».
    Породжувальний шар суперечив перевіряльному, а примітка «потрібне відлуння»
    цього не рятувала: композитор виконав би специфікацію буквально й отримав блокер.
    Тепер акцент розкладається на двох носіїв; якщо носій один — специфікація вимагає
    оголошеної фокусної зони, інакше вона невиконанна і про це сказано прямо."""
    ролі = {s: ДЕФОЛТ_РОЛЕЙ.get(s, "акцент") for s in слоти}
    if not S["відлуння"]: return ролі
    носії = [s for s in слоти if s in НОСІЇ_АКЦЕНТУ]
    for s in носії[:2]: ролі[s] = "акцент"
    return ролі

def поріг_кольору(h, L=None):
    """Нижче цієї C* тон у цій ділянці читається нейтраллю — обернене до outfit.нейтраль().

    ВИПРАВЛЕНО: функція не знала про нейві-виняток. outfit.нейтраль для ТЕМНИХ холодних
    (L*<=45) підіймає стелю з 24 до 34, а тут стояло глухе 24 — отже генератор видавав
    вікно C*∈[26..] на L*30 як «колір», перевіряльник називав ту саму річ нейтраллю,
    схема вироджувалась і гейт блокував акцент як сироту. Третій рецидив
    «генератор проти перевіряльника»; тепер виняток читається з ОДНОГО місця."""
    if 230 <= h <= 300:
        темна_зона = O.C["cool_neutral"][2], 34.0
        return 34.0 if (L is not None and L <= 45.0) else float(темна_зона[0])
    if 45 <= h <= 115: return float(O.C["warm_neutral"][2])
    return float(O.C["neutral_C"])

def здійсненність(L_вікно, дуга, C_вікно):
    """ЗНАЙДЕНО ЗАМКНЕНИМ ЦИКЛОМ: специфікація просила приглушений синій (h≈230, C≈24)
    на L*30 — а стеля гамуту там C=21. Річ, зібрана за таким вікном, фізично не може
    бути кольором: вона впаде в коридор холодних нейтралей, схема вироджується в
    «нейтрали+акцент», і гейт заблокує акцент як сироту. Вікно, якого не існує,
    гірше за відсутнє: композитор шукатиме в каталозі те, чого не буває.
    Тому кожне вікно звіряється з гамутом ДО видачі.

    R-COL-12 (тема-2): стеля береться з РЕАЛЬНИХ ПОВЕРХОНЬ (Pointer 1980), не з
    гамуту дисплея. Питання гейту — «чи може цим бути фарбована тканина», а не «чи
    існує такий піксель». Виміряно: sRGB пропускає 89.4% простору, реальні поверхні
    84.6% → 8.5% вікон були ФАНТОМНІ (пропущені й незаповнювані). Кластер —
    L*≈20, h 50–120°: темна олива, хакі, глибока гірчиця, тобто густо заповнена
    полиця українського рітейлу.

    ЧЕСНО: у корпусі відтворено 8 із 576 вузлів Pointer. На відомих вузлах діє
    виміряна стеля; у задокументованій зоні фантомів гейт говорить навіть коли sRGB
    пропускає; на решті стеля лишається sRGB — і це видно в полі `стеля_джерело`,
    а не замовчано."""
    if дуга is None: return dict(ok=True)
    a, b = дуга
    кути = [a + i*(((b - a) % 360) or 1)/6 for i in range(7)]
    вузли = [(cs.c_max_поверхня(L, h % 360), L, h % 360)
             for L in range(int(L_вікно[0]), int(L_вікно[1])+1, 2)
             for h in кути]
    найкраще = max(вузли, key=lambda v: v[0][0], default=((0.0, "—"), 0, 0))
    (стеля, джерело), L_опт, h_опт = найкраще
    # ВИПРАВЛЕНО ПІСЛЯ ДРУГОГО ПРОГОНУ ЦИКЛУ: перевіряти треба не «чи існує колір»,
    # а «чи може він НЕ бути нейтраллю». Приглушений синій на L*30 має стелю C*21 —
    # формально задовольняє C_min=14, але 21 < 24, тобто лежить у коридорі холодних
    # нейтралей, і гейт справедливо називає схему виродженою.
    _h_сер = (a + (((b - a) % 360)/2)) % 360
    _пн = поріг_кольору(_h_сер, L_опт)      # поріг залежить і від СВІТЛОТИ (нейві-зона)
    треба = max(C_вікно[0], _пн + 2)
    ок = стеля >= треба
    # Зона фантомів: тут sRGB систематично завищує стелю (39 проти 21 на L*20 h50°;
    # 28 проти 12 на L*20 h90°). Якщо ОПТИМУМ вікна впав сюди, а стеля прийшла з sRGB,
    # «ok» не є виміром — це припущення, і воно позначається окремо, бо саме на цих
    # вузлах правка й міряє свою користь.
    фантом = (cs.у_фантомній_зоні(L_опт, h_опт) and джерело.startswith("sRGB"))
    return dict(ok=ок, стеля=round(стеля, 1), треба=round(треба, 1),
                поріг_нейтралі=_пн, стеля_джерело=джерело,
                підозра_фантома=фантом,
                чому_підозра=("вузол лежить у задокументованій зоні фантомних вікон "
                              "(L*15–27, h 45–125°), а стеля тут прийшла з гамуту "
                              "ДИСПЛЕЯ: на сусідніх виміряних вузлах Pointer sRGB "
                              "завищує стелю вдвічі (39 проти 21 на L*20 h50°). "
                              "Вікно може бути незаповнюване тканиною"
                              if фантом else None),
                L_де_найширше=L_опт, h_де_найширше=round(h_опт, 1))

# ─── головний вхід ────────────────────────────────────────────────────────────
def _тримає_колір(L_вікно, ролі_дуги, S, intent):
    """Чи може ХОЧ ОДНА кольорова роль біля обличчя бути кольором на цій смузі.

    Рішення ухвалює наявна `здійсненність` (стеля реальних поверхонь проти порогу,
    за яким тон читається нейтраллю) — нового числа не заведено."""
    for роль, дуга in ролі_дуги:
        C_ = list(S["хрома"][роль])
        if C_[1] > ГУЧНО and intent == "conventional":
            C_[1] = ГУЧНО - 1
        if здійсненність(L_вікно, дуга, C_)["ok"]:
            return True
    return False


def _сторона_біля_обличчя(P, особа, слоти, схема, ролі, S, тони, intent):
    """Обрати, з якого боку від шкіри стоїть річ біля обличчя — ДО побудови драбини.

    ЗНАЙДЕНО ПРОГОНОМ НА ДВОХ ПРОТИЛЕЖНИХ КОЛОРИТАХ (`measure_hue_reach`), не тестом
    шару. `поверхи()` рахувала обидві сторони приобличчевого вікна, а споживач був
    лише в темнішої: `grep` по всьому дереву давав для `світле_біля_обличчя` рівно
    один рядок — той, що його створює.

    ЩО ЦЕ ЛАМАЛО. `цільове_вікно` віднімає контраст особи від L* шкіри. На темній
    шкірі різниця впирається в підлогу шкали: L*31.6 з контрастом 20.5 дає вікно
    [0,23]. У синьо-фіолетовій дузі на такій світлоті стеля реальних поверхонь
    C*29.6, а поріг, за яким тон перестає читатись нейтраллю, там 34 (виняток
    нейві) — отже роль оголошувалась виродженою, схема переходила на відлуння, і
    КОЛІРНА ВІСЬ ДЛЯ ТЕМНОГО КОЛОРИТУ ЗНИКАЛА ЦІЛКОМ: у фід ішли самі нейтральні
    вікна. Виміряно: у темної людини 4 рядки від рис і всі на «взуття», у світлої —
    12 на три слоти. Це та сама нерівність, яку знімає R-PC-09, тільки на осі
    світлоти, і вона не була видима жодному тесту, бо «вироджена роль» — законний
    стан системи, а не помилка.

    ЧОМУ ЦЕ НЕ НОВЕ ПРАВИЛО: `outfit.цільове_вікно` прямо каже «двобічне: річ може
    бути темнішою або світлішою за обличчя — обидві гілки легітимні». Темніша була
    ЗАШИТА, а не обрана. Темніша лишається першою (на світлій шкірі поведінка не
    міняється — перевірено), світліша пробується ЛИШЕ коли перша не тримає кольору.

    ⚠ ДЕ ЛАМАЄТЬСЯ. Вибір сторони — це вибір ОБРАЗУ («світліше за обличчя» проти
    «темніше»), а тут його робить ГАМУТ. Це законно як ПІДЛОГА (краще світліша
    сторона, ніж жодного кольору), але не як перевага: сторона названа в
    `P["сторона"]`, щоб шар вище міг її перебити нагодою чи бажанням людини.
    Друге обмеження: сторона обирається ОДИН раз, за первинними ролями. Якщо ролі
    перебудуються на відлуння, сторона не переглядається — це видно у виході, а не
    замовчано."""
    приобличчеві = [s for s in слоти
                    if O.SLOT_NEAR_FALLBACK.get(s, 0.2) >= O.NEAR_МІН]
    ролі_дуги = [(ролі[s], тони[ролі[s]]) for s in приобличчеві
                 if тони.get(ролі[s]) not in (None, "нейтраль")]
    if not ролі_дуги:
        return P                      # біля обличчя нема кольорової ролі — нема питання
    if _тримає_колір(P["біля_обличчя"], ролі_дуги, S, intent):
        return P
    if not _тримає_колір(P["світле_біля_обличчя"], ролі_дуги, S, intent):
        return P                      # не тримає жодна — сторона нічого не рятує
    P2 = поверхи(особа, слоти, схема, сторона="світліша")
    P2["сторона_чому"] = (
        "темніша сторона приобличчевого вікна %s не тримає кольору в дузі схеми "
        "(стеля реальних поверхонь нижча за поріг, за яким тон читається "
        "нейтраллю) — узято світлішу %s. Обидві сторони легітимні "
        "(outfit.цільове_вікно); рішення ухвалене гамутом, не нагодою, тож шар "
        "вище може його перебити" % (P["біля_обличчя"], P2["біля_обличчя"]))
    return P2


def _відступ_хроми(зд, C_схеми):
    """Вікно хроми для ролі, яка НЕ МОЖЕ нести колір на своїй світлоті.

    ЗНАЙДЕНО ПРОГОНОМ НА ТЕМНОМУ КОЛОРИТІ (`measure_hue_reach`). Тут стояло
    `[стеля*0.6, стеля*0.95]`, де `стеля` — стеля ГАМУТУ. На яскравих дугах вона
    доходить до C*114, і вироджений слот «низ» ішов у фід із вікном C*[68..108] —
    хромою, якої в масмаркеті не буває взагалі. Тобто відступ від «кольору тут не
    буває» був вікном, у якому не буває нічого: фільтр гарантовано порожній, а
    порожній він мовчки, бо запис виглядав як звичайний рядок.
    Це той самий дефект «вікна, якого не існує», проти якого написана
    `здійсненність` — просто на гілці, куди вона сама й веде.

    ЩО ЗМІНИЛОСЬ У РІШЕННІ: стеля відступу більше не може перевищити стелю хроми,
    яку оголосила СХЕМА (C_схеми[1]). Схема — це твердження про образ; гамут — про
    фізику. Відступ не має права просити гучніше, ніж просила схема.

    ⚠ ДЕ ЛАМАЄТЬСЯ: 0.6 як нижня межа відступу лишається запозиченим числом (T3,
    фольклорна константа) — воно не каліброване й тут не калібрується. Правка
    знімає ФАНТОМ, а не невизначеність ширини."""
    стеля = min(float(C_схеми[1]), float(зд["стеля"]))
    return [round(стеля * 0.6), round(стеля)]


def специфікація(F, схема, слоти, якір_тон=None, source="uncontrolled",
                 intent="conventional", фокус=None, принт=None, драп=None, мета="лестити",
                 самозвіт=None):
    """Вихід — фільтр каталогу на кожен слот. Нічого не вирішує про смак:
    схему й якір дає композитор, тут лише арифметика під цю особу.

    якір_тон: кут тону (0–360) або hex речі, від якої будується схема. Якщо не
    заданий — береться тон очей, але ЛИШЕ коли надійність хроми це дозволяє
    (K-PC-05); інакше повертається схема без тонових обмежень і питання людині.

    принт: dict(палітра=<вихід feed.палітра_принту>, слот="сукня") — коли одна річ
    образу принтована. Тоді її внутрішня палітра закриває РОЛІ, сольний слот дістає
    ехо-запит (повтор кольору принту), а гучність принту неперервно піднімає
    перевагу нейтралі в решті слотів. Без цього параметра принт до композитора не
    доходив узагалі — палітра принту вимірювалась і викидалась."""
    if схема not in СХЕМИ:
        raise ValueError(f"невідома схема {схема}; є: {sorted(СХЕМИ)}")
    особа = O.контраст_особи(F, source)
    if not особа.get("доступно"):
        raise ValueError("нема профілю особи: " + особа.get("чому", ""))
    R = reliability(source)
    P = поверхи(особа, слоти, схема)
    S = СХЕМИ[схема]

    тон_доступний = R["hue"] >= MIN_TO_EMIT
    if isinstance(якір_тон, str): якір_тон = lch(hx(якір_тон))[2]
    if якір_тон is None and (F.get("очі") or {}).get("h") and тон_доступний:
        якір_тон = F["очі"]["h"]
    тони = S["тон"](якір_тон) if якір_тон is not None else {r: None for r in РОЛІ}

    def поле_слота(слот, роль):
        """Вікно для слота будується ПІСЛЯ того, як роль остаточна. Раніше слот,
        підвищений до акценту через виродження, лишався з вікном секунданта —
        і специфікація вимагала кольору у смузі, де його не буває."""
        near = O.SLOT_NEAR_FALLBACK.get(слот, 0.2) >= O.NEAR_МІН
        L = (P["біля_обличчя"] if near else
             P["акцент_L"] if роль == "акцент" else P["секундант_L"])
        C_ = list(S["хрома"][роль]); t = тони[роль]
        if near and C_[1] > ГУЧНО and intent == "conventional":
            C_[1] = ГУЧНО - 1
        поле = dict(роль=роль, L=L, C=C_)
        if t == "нейтраль":
            # ЗНАЙДЕНО ПРОГОНОМ ПО ФІДУ: тут стояло C*<12, і вікно порожніло на речах,
            # які outfit.нейтраль() спокійно вважає нейтралями (кемел C*31, хакі C*19).
            # Генератор був суворіший за перевіряльник — два визначення нейтралі в
            # одній системі. Тепер визначення ОДНЕ: перевірка йде через outfit.нейтраль,
            # а вікно лише окреслює світлоту й стелю найширшого коридору.
            поле["сім_я"] = ("нейтраль за коридорами K-COL-06 (ахроматична C*<12, тепла "
                             "h45–115 C*≤34, холодна h230–300 C*≤24); одна сім'я на образ, "
                             "крос лише з кроком ΔL*≥12")
            поле["C"] = [0.0, 34.0]
            поле["тест"] = "outfit.нейтраль(lab) is not None"
            # НАПРЯМ B: температура нейтралі-якоря — тут, а не в розвилці, щоб джерело
            # було одне й прямий виклик специфікація() теж її отримував.
            як = нейтраль_якір(F, source=source, слот=слот, intent=intent,
                               драп=драп, мета=мета)
            if як.get("придатно") and not як["вільно"]:
                поле["нейтраль_темп"] = як
            поле["сім_я"] = поле["сім_я"] + (
                "; температура: " + як["нота"] if як.get("придатно") else "")
            return поле, False
        if t is None:
            поле["тон"] = "не обмежено: підтон і тон не стверджуються з цього фото (K-PC-05)"
            return поле, False
        поле["дуга_тону"] = t
        зд = здійсненність(L, t, C_); поле["здійсненність"] = зд
        if зд["ok"]:
            lo = max(C_[0], зд["поріг_нейтралі"] + 2); hi = min(C_[1], round(зд["стеля"]))
            if hi <= lo:      # вікно вивернулось: стеля гамуту нижча за поріг кольору
                поле["C"] = _відступ_хроми(зд, C_)
                поле["попередження"] = (f"вікно вивернулось (C_min {lo} > C_max {hi}): "
                    f"стеля гамуту C*{зд['стеля']} не лишає місця над порогом нейтралі "
                    f"{зд['поріг_нейтралі']} — роль не може бути кольоровою")
                return поле, True
            поле["C"] = [lo, hi]
            return поле, False
        поле["C"] = _відступ_хроми(зд, C_)
        поле["попередження"] = (
            f"на L*{L[0]}–{L[1]} у цій дузі гамут дає максимум C*{зд['стеля']}, "
            f"а щоб не читатись нейтраллю треба C*>{зд['поріг_нейтралі']}: "
            "роль фізично не може нести колір на цій світлоті")
        return поле, True

    ролі = розподіл_ролей(слоти, S, фокус)
    P = _сторона_біля_обличчя(P, особа, слоти, схема, ролі, S, тони, intent)
    вихід, вироджені = {}, []
    for слот, роль in ролі.items():
        вихід[слот], вирод = поле_слота(слот, роль)
        if вирод: вироджені.append(слот)

    акцентні = [s for s, r in ролі.items() if r == "акцент"]
    примітки = [S["ризик"], P["примітка"]]
    if вироджені:
        примітки.append(f"схема вироджується: {вироджені} не можуть нести колір на своїй "
                        "світлоті (гамут) і читатимуться нейтралями — фактично це "
                        "«нейтрали+акцент», отже акцент потребує другого носія")
        S = dict(S, відлуння=True)
        ролі = розподіл_ролей(слоти, S, фокус)
        вироджені = []
        for слот, роль in ролі.items():        # вікна перебудовуються під нові ролі
            вихід[слот], вирод = поле_слота(слот, роль)
            if вирод: вироджені.append(слот)
    # ── ТЕМПЕРАТУРА НЕЙТРАЛІ-ЯКОРЯ: РАХУЄТЬСЯ ДЛЯ ЯКІРНОГО СЛОТА ЗАВЖДИ ────────
    # `нейтраль_темп` вище ставиться ЛИШЕ в гілці `t == "нейтраль"` — тобто там, де
    # СХЕМА дала слотові нейтральний тон. Слоти-якорі («взуття», «сумка», «пояс»,
    # «колготи») дістають від схеми КОЛЬОРОВУ роль майже завжди — і саме тому
    # `запит_у_фід` додає їм окремий нейтральний рядок. Дві умови виявились
    # взаємовиключними за побудовою: рядок читав поле, якого в такому слоті не
    # буває, і його температурна гілка не спрацювала жодного разу на 456 живих
    # рядках (Н-palette-2-099) — температура особи в добір нейтралі не доїжджала.
    # Тепер вікно рахує та сама `нейтраль_якір` на тих самих F/source/intent/драп/
    # мета і лягає в ОКРЕМЕ поле. Ім'я окреме свідомо: `нейтраль_темп` означає
    # «слот сам по собі нейтральний за схемою», `якір_нейтраль_темп` — «слотові
    # додається запасний нейтральний рядок, ось його температура».
    # `вільно=True` поля НЕ дістає: для далеких слотів («взуття» near 0.00,
    # «колготи» 0.00) вага вікна нульова, b-межі вироджуються в увесь простір
    # нейтралей, і таке «вікно» було б безмежним твердженням замість обмеження.
    for _слот_якір in ЯКІРНІ_СЛОТИ:
        if _слот_якір not in вихід: continue
        як = нейтраль_якір(F, source=source, слот=_слот_якір, intent=intent,
                           драп=драп, мета=мета)
        if як.get("придатно") and not як["вільно"]:
            вихід[_слот_якір]["якір_нейтраль_темп"] = як
    акцентні = [s for s, r in ролі.items() if r == "акцент"]
    потребує_фокус = (S["відлуння"] and len(акцентні) < 2
                      and not (фокус and set(акцентні) & set(фокус)))
    if потребує_фокус:
        примітки.append(f"НЕВИКОНАННО як є: схема тримається на відлунні, а носіїв "
                        f"акценту {len(акцентні)}. Додати другий носій ({', '.join(НОСІЇ_АКЦЕНТУ[:4])}) "
                        f"або оголосити {акцентні or 'акцентний слот'} фокусною зоною — "
                        "інакше outfit.py заблокує образ як сироту-акцент")
    if not тон_доступний:
        примітки.append("тон і підтон загейтовані джерелом: питати людину про метали "
                        "й білі, працювати у value-термінах")
    # ── ПРИНТ (напрям A): палітра принту доходить до композитора ────────────────
    принт_вихід = None
    if принт and принт.get("палітра"):
        рп = роль_принту(принт["палітра"], list(вихід), принт.get("слот"), intent=intent)
        принт_вихід = рп
        сл_принту = принт.get("слот")
        if сл_принту in вихід:
            вихід[сл_принту]["несе_принт"] = dict(закриває=рп["закриває"],
                                                  гучність=рп["гучність"])
        q = рп.get("запит_ехо")
        if q and q["слот"] in вихід:
            # ехо не перезаписує поле слота, а лягає поруч: рішення несе `сила`
            вихід[q["слот"]]["принт_ехо"] = q
        # гучність принту неперервно піднімає перевагу нейтралі в РЕШТІ слотів
        for сл, в in вихід.items():
            if сл != сл_принту:
                в["нейтраль_перевага"] = рп["нейтраль_перевага"]
        примітки.append(
            "принт у слоті %s закриває %s; ехо-акцент → %s (сила %.2f); "
            "нейтраль-перевага решти слотів %.2f" % (
                сл_принту, рп["закриває"] or "—",
                (q["слот"] if q else "нема куди"), (q["сила"] if q else 0.0),
                рп["нейтраль_перевага"]))

    # ── ТОН ВІД РИС: друга, незалежна від якоря-схеми тонова вісь ─────────────
    # Крок 2 задачі 42 живе саме тут: вихід НЕСЕ, яка вісь звідки і що зняло б
    # утримання. До цього мовчання тону було невідрізнене від «пораховано й
    # вийшло широко» — два різні стани під одним порожнім полем.
    тв = тон_від_рис(F, схема, source=source, intent=intent)
    # ── ПЕРСОНАЛЬНА ПАЛІТРА (24.08.2026): зона в LCh від рис, з ролями й рангами ──
    # Доти світлота й хрома ЛЮДИНИ у фід не доходили (рядок від риси копіював L і C
    # з вікна схеми), а дуги рис ішли рівноправно. Палітра — окремий об'єкт у спец:
    # її читає бриф (personal_palette.словами) і запит_у_фід (рядки з рангом риси).
    import personal_palette as _PP
    палітра_особи = _PP.палітра(F, source=source)
    # ── ПРАКТИКОВИЙ ШАР ПАЛІТР (24.08.2026, palettes.py): позиція на трьох осях →
    # палітра, що поділяє домінанту людини (Sci\ART/Kalisz, Lamport, JPCA), конкретні
    # кольори з назвами, прийоми як оператори. Контраст особи — той самий, що в розвилці.
    import palettes as _PL
    try:
        _рівень = O.контраст_особи(F, source=source).get("рівень")
    except Exception:
        _рівень = None
    # ── САМОЗВІТ У ПРАКТИКОВУ ПАЛІТРУ (Н-V03-007) ────────────────────────────
    # Параметр `самозвіт` у `palettes.палітра_практична` стояв від початку, і жоден
    # продуктовий викликач його не передавав — ні цей рядок, ні `composer`. Тому
    # на живому шляху (`uncontrolled`) вісь тону утримувалась ЗАВЖДИ, метал палітри
    # лишався «обидва», а той самий пакет казав про метал дві різні відповіді:
    # `bridge._основи` бачив самозвіт і відповідав «золото», картка брифа — ні.
    палітра_практична = _PL.палітра_практична(F, source=source, самозвіт=самозвіт,
                                              контраст_рівень=_рівень, intent=intent)
    if тв["придатно"]:
        живі = [nm for nm, d in тв["риси"].items() if d.get("дуги")]
        німі = [nm for nm, d in тв["риси"].items() if not d.get("дуги")]
        примітки.append(
            "тон від рис: голосують %s%s; перегуків %d, напруг %d. Риси НЕ "
            "усереднюються — кожна дає власний рядок запиту"
            % (", ".join(живі) or "жодна",
               (" (мовчать: %s — ахроматичні)" % ", ".join(німі)) if німі else "",
               len(тв["перегуки"]), len(тв["напруги"])))
    else:
        примітки.append("тон від рис УТРИМАНО (%s): %s. Зняло б: %s"
                        % (тв["утримано"]["правило"], тв["утримано"]["чому"],
                           тв["утримано"]["що_зняло_б"]))

    return dict(схема=схема, потребує_фокус=потребує_фокус, вироджені_ролі=вироджені or None, якір_тон=(round(якір_тон, 1) if якір_тон is not None else None),
                принт=принт_вихід, тон_від_рис=тв, палітра=палітра_особи,
                палітра_словами=_PP.словами(палітра_особи),
                палітра_практична=палітра_практична,
                палітра_практична_словами=_PL.словами(палітра_практична),
                намір=intent, контраст_особи=особа["value_gap"],
                слоти=вихід, примітки=примітки,
                статус="усі межі T3, не калібровані; вихід придатний як фільтр фіду, "
                       "не як обіцянка, що така річ у каталозі є")

def розвилка_специфікацій(F, слоти, source="uncontrolled", intent="conventional",
                          якір_тон=None, фокус=None, драп=None, мета="лестити",
                          самозвіт=None):
    """ГОЛОВНИЙ вхід замість `специфікація` для одного вибору: віддає РОЗВИЛКУ
    каталожних фільтрів — по одному на кожну законну схему цього колориту, з вагою
    згоди. Retrieval тягне гарнітури під КОЖНУ гілку; фінальну палітру обирає людина.

    Гілки, що мапляться на реальну схему в СХЕМИ, отримують повну специфікацію +
    плаский запит у фід. Гілки-концепти (контраст-мисматч) НЕ фабрикуються у спец —
    вони потребували б послаблення приобличчевого вікна в поверхи(), чого ще нема;
    вони проходять як позначена опція зі статусом «не реалізовано як фільтр», а не
    як фейковий запит (правило 6)."""
    особа = O.контраст_особи(F, source)
    if not особа.get("доступно"):
        raise ValueError("нема профілю особи: " + особа.get("чому", ""))
    R = розвилка(особа, intent=intent)
    # ── ОДНЕ ПИТАННЯ — ОДНА ВІДПОВІДЬ У МЕЖАХ ОДНОГО ВИХОДУ (Н-V04-011) ───────
    # Поле `температура` цього виходу рахувалось без самозвіту, тоді як палітра в
    # гілках його вже чула. Той самий пакет казав про метал двоє різного: основи
    # «срібло» (бачили картки), картка брифа «обидва» (не бачила). Суперечність
    # жила не в правилах, а в тому, що один і той самий канал доходив до одного
    # поля виходу й не доходив до сусіднього.
    темп = температура(F, source, intent, самозвіт=самозвіт)

    гілки_out = []
    for g in R["гілки"]:
        рядок = dict(g)   # копія: схема, вага, коли, застереження, [хрома_акценту]
        if g["схема"] in СХЕМИ:
            спец = специфікація(F, g["схема"], слоти, якір_тон=якір_тон,
                                source=source, intent=intent, фокус=фокус,
                                драп=драп, мета=мета, самозвіт=самозвіт)
            рядок["спец"] = спец
            зфід = запит_у_фід(спец)
            # ТЕМПЕРАТУРА тепер впорскується НЕПЕРЕРВНО і ПО-СЛОТНО (напрям B).
            # Було: бінарний гейт + одна дуга тону на всі нейтральні рядки, причому
            # feed.підходить її не читав (ранній return) — впорскування було інертним.
            # Стало: кожен нейтральний рядок дістає своє вікно b* за власним near,
