def конкуренція(_t, об, intent="conventional"):
    """K-SIL-01: одна читабельна форма = один відліт контуру від тіла нижче плечей.

    `_t` НЕ ЧИТАЄТЬСЯ СВІДОМО: сигнатура одна на ланцюг форми (`конкуренція` + `об_єм`
    + `зонні_операції` + `нічия_стратегія` складаються поряд), а відліт і глибина
    долини міряються на ОБГОРТЦІ, у якій масштаб тіла уже стоїть (`об["масштаб_тіла"]`)."""
    в = відльоти(об)
    if в["кількість"] < 2: return []
    точки = в["точки"]
    носії = sorted({т["носій"] for т in точки if т["носій"]})
    опис = "; ".join(f"«{т['рівень']}» {т['ширина']} см (вихід від «{т['від']}», "
                     f"виразність {т['виразність']}, від «{т['носій']}»)" for т in точки)
