# ПОРІГ 2 % І ЧОМУ ВІН ТАМ. Нижче 2 % еластан у полотні — стабілізатор (річ не
# тягнеться, лише тримає форму); від 2 % починається та розтяжність, через яку припуск
# перестає бути мірою прилягання. Це не калібрована межа, і `ламається` кожної
# знахідки K-BOD-02 уже казало те саме своїми словами: «смуги лагодять АРИФМЕТИКУ, не
# залежність від тканини… драп не виміряний — це найімовірніше джерело хибних
# спрацювань». Тепер один із двох каналів тканини виміряний, і знахідка це показує.
# ЧОМУ ОДИН КРОК ЛАДДЕРА, А НЕ ПИТАННЯ Й НЕ ТИША. Питання — це «входу нема»; тут вхід
# Є (склад оголошений), і геометрія справді від'ємна. Тиша була б протилежною помилкою:
# бодікон із 18 % еластану, який облягає широку зону, лишається тим, що бачить око.
# Тому вердикт лишається й називає, ЧИМ вирішено прилягання — розтяжністю, не кроєм.
# КРОК ВІДНОСНИЙ, А НЕ «strong → soft» ЛІТЕРАЛОМ, І ЦЕ ЗНАЙДЕНО ПРОБОЮ. K-BOD-02 стоїть
# на константі тіру T3, тож `_зн` уже зрізає заявлений `strong` до `soft` («стеля тіру»).
# Перша редакція цієї функції перевіряла `сила == "strong"` — і не спрацьовувала НІКОЛИ:
# на вхід їй завжди приходило `soft`. Тому крок рахується від тієї сили, яка в знахідки
# справді є, і не опускається нижче за `hint`.
_ЕЛАСТАН_ПОРІГ = ЕЛАСТАН_ПОРІГ        # одне число з гілкою мінімумів (`силует_припуск`)
_ЛАДДЕР_СИЛИ = ("hard", "strong", "default", "soft", "hint")


def _провенанс_еластану(зн, частка, за_чим):
    """Звідки число еластану, на якому стала сила (01.10.2026, рядок 305).

    `еластан_за_чим` лежало в речі каталогу без читача: «склад оголошує 18 %» і «волокно
    назване, частки нема» вели до різного, а звіт власника не бачив, котре з двох.
    Поле йде в `діагностика` — числа для розробника, які мовний гейт не читає й жінці
    не показують (`реєстр_сила._зн`); міст везе їх у `етапи.суд.знахідки` звіту."""
    зн = dict(зн)
    зн["діагностика"] = dict(зн.get("діагностика") or {}, еластан_відсотків=float(частка),
                             еластан_за_чим=list(за_чим or []) or None)
    return зн


def _на_еластані(зн, частка, за_чим=None):
    """K-BOD-02 «облягає» на тканині з еластаном: сила на крок нижче, причина названа.

    Той самий спосіб, що `_над_дефолтним_кроєм`: сила, регістр і `сила_нп` беруться
    з категорії, а не правляться на око. Знахідка не зникає — слабшає, бо вікно
    ковзання опубліковане для полотна."""
    if частка is None or float(частка) < _ЕЛАСТАН_ПОРІГ:
        return зн
    якщо = зн.get("сила")
    if якщо not in _ЛАДДЕР_СИЛИ:
        return зн                        # «питання» ладдером не йде: там входу нема
    нижче = _ЛАДДЕР_СИЛИ[min(_ЛАДДЕР_СИЛИ.index(якщо) + 1, len(_ЛАДДЕР_СИЛИ) - 1)]
    зн = dict(зн)
    зн["сила"] = нижче
    зн["регістр"] = _РЕЄСТР_П.регістр(зн["правило"], нижче)
    зн["блокує"] = (зн["регістр"] == "гейт")
    зн["сила_нп"], _ = _РЕЄСТР_П._неперервна_сила(нижче)
    зн["сила_нп_джерело"] = ("категорія: склад оголошує %g %% еластану — вікно "
                             "ковзання опубліковане для полотна (сила з «%s» на «%s»)"
                             % (float(частка), якщо, нижче))
    зн["примітка"] = ((зн.get("примітка") + ". ") if зн.get("примітка") else "") + (
        "склад: еластану %g %% — прилягання вирішує розтяжність, не припуск крою"
        % float(частка))
    зн["заяви"] = list(зн.get("заяви") or []) + [
        _ВМ.заява("fabric_stretches_ease_window_weaker", elastane_percent=float(частка))]
    return _провенанс_еластану(зн, частка, за_чим)


