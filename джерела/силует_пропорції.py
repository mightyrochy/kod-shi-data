    if сл == "пояс":
        return ("слот", "belt_item")
    if сл not in СЛОТИ_ТАЛІЇ:
        return None
    т = r.get("талія")
    if т in ТАЛІЯ_ДЕТАЛЬ and сл in ТАЛІЯ_ДЕТАЛЬ[т][1]:
        return ("талія", ТАЛІЯ_ДЕТАЛЬ[т][0])
    import outfit as _O
    к = _O.крій_речі(r)
    if к in КРІЙ_НА_ТАЛІЇ:
        return ("крій", КРІЙ_НА_ТАЛІЇ[к])
    д = [x for x in (r.get("деталі_крою") or ()) if x in ДЕТАЛІ_КРОЮ_НА_ТАЛІЇ]
    if д:
        return ("деталі_крою", ДЕТАЛІ_КРОЮ_НА_ТАЛІЇ[д[0]])
    if сл == "верхній_шар" and r.get("пояс") is True:
        return ("пояс", "belt")
    return None


