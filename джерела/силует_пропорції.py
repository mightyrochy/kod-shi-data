def площа(об, ключ="ширина"):
    """Інтеграл ширини по висоті — фронтальна площа обгортки (або тіла)."""
    S = 0.0
    for a, b in zip(об, об[1:]):
        S += (a[ключ] + b[ключ]) / 2 * abs(a["см"] - b["см"])
    return S


def якорі(об, t=None):
    """Рівні, де тіло видно: припуск нижче порога прилягання, або зона гола.
    Це те, що корпус зве «талія або відкриті вузькі точки».

    На тілі без вузької точки на талії (`fit.зони` → O, FFIT Oval/Diamond) талія —
    не якір: пояс на природній талії й облягання середини для O — anti `strong` (K-BOD-02,
    тема-4:946)."""
    вузькі = ("щиколотка", "коліно") if без_талії(t) else ("талія", "щиколотка", "коліно")
    out = []
    for з in об:
        if з["рівень"] not in вузькі: continue
        if not з["одягнено"]:
            out.append(dict(рівень=з["рівень"], вид="гола вузька точка"))
        else:
            # припуск — відношення двох ширин (виріб/тіло): якір називаємо лише понад його похибку (п.6, ч19);
            # відрізок у межах похибки торкається обох боків порога чи похибки нема — вид «невідомо», і
            # «якоря нема» тут не твердять (K-SIL-03 мовчить, доки якір не відомий)
            к = категорії_в_похибці(з["припуск"], з.get("похибка_припуску"), (C["якір_прилягання"] + 1e-9,))
            if к == (0,):
                out.append(dict(рівень=з["рівень"], вид=f"прилягання {з['припуск']}"))
            elif len(к) > 1:
                out.append(dict(рівень=з["рівень"], вид="невідомо"))
    return out


def без_талії(t):
    """Чи тіло маршрутизоване як O: Oval/Diamond за каскадом FFIT."""
    о = (t or {}).get("обхвати") or {}
    return bool(all(о.get(к) for к in ("плечі", "груди", "талія", "стегна")) and ПС.зони(t)["ярлик"] == "O")


СТАТУРИ = ("тонка/середня", "на межі, рампа", "повна")   # за порогами статура_рампа_від / статура_рампа_до


def множник_статури(t):
    """(множник 0.35–1.0, індекс, нота) — §10.2 теми-3: штраф об'єму залежить від статури.
    Без обхвату талії або зросту множник 1.0 і нота «статура невідома» (нічого не вгадуємо).

    Категорію статури за талія/зріст код називає лише понад похибку обох вимірів (рішення менеджера 06.11
    «п.6: крок обчислення і два виміри тіла»): похибка відношення — whtr·(e_талії/талія + e_зросту/зріст)
    з `похибка_виміру_тіла`. Відрізок у межах похибки торкається кількох категорій чи похибки нема — статуру
    не названо: множник 1.0 («штраф як для середньої», як без даних), а нота перелічує можливі категорії."""
    обх = (t or {}).get("обхвати") or {}
    зріст = (t or {}).get("зріст")
    if not обх.get("талія") or not зріст:
        return 1.0, None, "статура невідома (нема талії або зросту) — штраф як для середньої"
    whtr = float(обх["талія"]) / float(зріст)
    a, b, п = C["статура_рампа_від"], C["статура_рампа_до"], C["статура_підлога"]
    е_т, е_з = похибка_виміру_тіла(t, "талія"), похибка_виміру_тіла(t, "зріст")
    е = None if е_т is None or е_з is None else whtr * (е_т / float(обх["талія"]) + е_з / float(зріст))
    можливі = категорії_в_похибці(whtr, е, (a, b))
    if len(можливі) > 1:
        return 1.0, round(whtr, 3), (
            "талія/зріст %.2f: статура невідома — %s, тож вимір не розрізняє категорій %s; штраф як для середньої"
            % (whtr, "похибки талії й зросту нема" if е is None else "похибка відношення ±%.3f" % е,
               " / ".join(СТАТУРИ[і] for і in можливі)))
    ч = min(1.0, max(0.0, (whtr - a) / max(1e-6, b - a)))
    return round(1.0 - (1.0 - п) * ч, 3), round(whtr, 3), (
        "талія/зріст %.2f: %s (Fan 2003 — більша річ %s сприйнятий розмір)"
        % (whtr, СТАТУРИ[можливі[0]], ("додає", "змінює знак дії", "зменшує")[можливі[0]]))


def об_єм(t, об, intent=ТИПОВИЙ_НАМІР, *, прогін_руки=None):
    """K-SIL-03, ГЕОМЕТРИЧНО. Перша версія множила два теги припуску (relaxed×relaxed) і
    видавала добуток за вимір — маржа проти порога виходила 0.003, тобто число без сенсу.
    Тепер міряється відношення ПЛОЩ: скільки фронтальної площі образ додав до тіла."""
    S_од = площа(об, "ширина"); S_тіла = площа(об, "ширина_тіла")
    if S_тіла <= 0: return []
    к = S_од / S_тіла
    if к < C["об_єм_без_якоря"]: return _ПОЛ.злам("K-SIL-03", "об_єм", [], об=об, прогін_руки=прогін_руки)
    як = якорі(об, t)
    if any(я["вид"] != "невідомо" for я in як): return _ПОЛ.злам("K-SIL-03", "об_єм", [], об=об, прогін_руки=прогін_руки)
    if як:
        # якір не доведено ні в бік «є», ні «нема» (припуск у межах похибки або похибки нема): правило каже, що не
        # судить, і чого бракує, а не мовчить (Е3-одна-величина ч19, дошка 13932)
        _заяви = [_ВМ.заява("volume_anchor_not_judged_error_unknown",
                            levels=[_ВМ.код_або_невідомо("body_level", я["рівень"]) for я in як])]
        _н = _зн("K-SIL-03", "утримано", _ВМ.суть_кодом(_заяви),
                 sorted({з["носій"] for з in об if з["носій"]}),
                 f"фронтальна площа образу {S_од:.0f} см² проти {S_тіла:.0f} см² тіла — відношення {к:.2f} при порозі "
                 f"{C['об_єм_без_якоря']}; чи є якір об'єму, код не судить: припуск на рівнях "
                 + ", ".join(я["рівень"] for я in як) + " у межах похибки обхватів або похибки нема",
                 примітка="K-IO-05: якір — лише понад похибку припуску; інакше «невідомо»")
        _н["заяви"] = _заяви
        return [_ПОЛ.злам("K-SIL-03", "справна", _н, прогін_руки=прогін_руки)]
    _о = без_талії(t)
    # ДРУГА ГРАНЬ ТІЄЇ САМОЇ ПОДІЇ, А НЕ ДРУГА ЗНАХІДКА. Корпусна умова «no anchor
    # -> no letter» (K-SIL-01) стояла тут окремою функцією `без_літери`, чий гейт
    # був СТРОГОЮ ПІДМНОЖИНОЮ цього: 312 збігів із 312, нуль самостійних спрацювань,
    # і той самий вимір відношення площ у двох знахідках. Тепер вона кваліфікує цю —
    # див. `_форма_не_читається`.
    без_форми = _форма_не_читається(об)
    гучні = sorted({з["носій"] for з in об
                    if з["носій"] and категорії_в_похибці(з["припуск"], з.get("похибка_припуску"),
                                                          (C["гучний_носій"],)) == (1,)})
    мн, whtr, нота_ст = множник_статури(t)
    зн = _зн(
        "K-SIL-03", "strong" if мн >= 1.0 else "default",
        ("повний об'єм без якоря, і форма не читається: контур нікуди не йде, талії нема"
         if без_форми else
         "повний об'єм без жодного якоря: тіла не видно ніде"),
        гучні,
        f"фронтальна площа образу {S_од:.0f} см² проти {S_тіла:.0f} см² тіла — "
        f"відношення {к:.2f} при порозі {C['об_єм_без_якоря']}; жоден із рівнів "
        f"талія/коліно/щиколотка не приляглий (припуск ≤ {C['якір_прилягання']}) і не "
        f"відкритий",
        запит=dict(слот="низ", крій=["straight", "tapered", "pencil"],
                   чому="K-SIL-03: якір об'єму"),
        вимір=к, поріг=C["об_єм_без_якоря"], повна=C["повна_об_єму"],
        ламається="площа фронтальна: об'єм, який іде вбік і назад (кокон, пуховик), "
                  "недооцінюється. Тканина теж не врахована — жорсткий твід тримає "
                  "форму, джерсі падає, а обгортка в обох однакова. Статура: класифікація "
                  "біля межі рампи (T3) і структурована проти м'якої тканини (драп не "
                  "контрольовано у Fan 2003)",
        примітка=None if intent in ПС.ФЛЕТЕРИНГ else
                 "за fashion-forward об'єм без якоря — свідомий кокон, не дефект")
    # §10.2: та сама річ — інша сила на іншому тілі (перед цим правило було незалежним від тіла)
    if мн < 1.0:
        зн["сила_нп"] = round((зн.get("сила_нп") or 0.0) * мн, 2)
        зн["сила_нп_джерело"] = (зн.get("сила_нп_джерело") or "") + "; × %.2f за статурою (%s)" % (мн, нота_ст)
    зн["статура"] = dict(множник=мн, талія_зріст=whtr, нота=нота_ст)
    # `також_правило` — щоб покриття коду K-SIL-01 цим механізмом не зникло зі
    # знахідки разом із окремим записом; `форма_не_читається` — щоб грань було
    # видно прапорцем, а не вгадувати її з тексту суті.
    зн["також_правило"] = "K-SIL-01"
    зн["форма_не_читається"] = без_форми
    # РІВНІ НЕ ЗВУЖУЮТЬСЯ: `об_єм` міряє інтеграл площі по ВСІЙ обгортці, тож
    # заглушка на будь-якому одягненому рівні псує вимір цілком — той самий
    # аргумент, що вже записаний у `відповідність`. Гейт стоїть після множника
    # статури й перед записом у трасу, щоб у трасу пішла та сила, яку побачить
    # людина, а не доgейтова.
    зн = _над_дефолтним_кроєм(зн, дефолтний_крій(об), заяви=[_ВМ.заява(
        "claim_volume_without_anchor_no_shape" if без_форми else "claim_volume_without_anchor")])
    _СЛ.запис("K-SIL-03", "volume_without_anchor_times_build", "silhouette.об_єм",
              значення="відношення площ %.2f; %s" % (к, нота_ст), сила=зн.get("сила_нп"))
    return [_ПОЛ.злам("K-SIL-03", "справна", зн, прогін_руки=прогін_руки)]


