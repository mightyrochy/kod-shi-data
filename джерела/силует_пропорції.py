def конкуренція(_t, об, intent=ТИПОВИЙ_НАМІР):
    """K-SIL-01: одна читабельна форма = один відліт контуру від тіла нижче плечей.

    КОД НЕ ЛІЧИТЬ ВІДЛЬОТІВ І НЕ СУДИТЬ (корінь Е3-одна-величина, п.2, вид межі 1; 06.11).
    Окремий відліт рахувався за порогом `виразність_відльоту` 0.10 ширини тіла — «моя оцінка»
    без джерела; пошук 06.11 порогу виразності відльоту не дав (див. `силует_лінії.відльоти`).
    Запис і порівняння знято: правило віддає одну знахідку `утримано` з виміряним контуром —
    ширина образу поруч із шириною тіла на кожному рівні, — а чи читається тут одна форма чи
    дві, судить стилістка («Код має знати те що може точно порахувати», власник 01.10).
    Вага `утримано` — нуль; над дефолтним кроєм знахідка, як і досі, — питання.

    `_t` НЕ ЧИТАЄТЬСЯ СВІДОМО: сигнатура одна на ланцюг форми (`конкуренція` + `об_єм`
    + `зонні_операції` + `нічия_стратегія` складаються поряд), а контур міряється на
    ОБГОРТЦІ, у якій масштаб тіла уже стоїть."""
    в = відльоти(об)
    контур = в["контур"]
    if len(контур) < 2: return []
    носії = sorted({т["носій"] for т in контур if т["носій"]})
    рівні = tuple(т["рівень"] for т in контур)
    заглушка = дефолтний_крій(об, рівні)
    заява_факт = _ВМ.заява("measured_contour_widths", contour=[
        [_ВМ.код_або_невідомо("body_level", т["рівень"]), т["ширина"], т["ширина_тіла"]] for т in контур])
    опис = "; ".join(f"«{т['рівень']}» образ {т['ширина']} см / тіло {т['ширина_тіла']} см"
                     + (f" («{т['носій']}»)" if т["носій"] else "") for т in контур)
    return [_над_дефолтним_кроєм(_зн(
        "K-SIL-01", "утримано",
        _ВМ.суть_кодом([заява_факт], носії),
        носії, учасники=dict(речі=носії, зони=ГР.зони_тіла(*рівні)),
        чому=f"контур згори вниз: {опис}. Межі «окремий відліт» джерела не дають — скільки "
             f"форм читається, код не лічить, судить стилістка",
        ламається="контур міряється по фронтальному припуску: об'єм, що йде назад "
                  "(турнюр, кокон), не рахується; рукав у профілі не бере участі",
        примітка=None if intent in ПС.ФЛЕТЕРИНГ else
                 "за fashion-forward кілька відльотів — свідома конструкція"), заглушка,
        заяви=[заява_факт])]
