def нічия_стратегія(t, об, intent="conventional"):
    """K-BOD-02 для H/нейтральної пари. Корпус тут вимогливіший, ніж до інших типів, і
    вимога СИНГУЛЯРНА: «створити талію АБО свідома колона — одна зі стратегій
    ОБОВ'ЯЗКОВА; нічия стратегія читається як мішок». Це єдиний тип, де відсутність
    ходу сама є провалом, — і саме тому зонні ролі тут мовчать: перекосу пари нема,
    карати нема що. Виміряно: без цього правила H пропускав 42% простору кроїв проти
    19% в A — тобто для найпоширенішої фігури фільтр не працював зовсім.

    Обидві стратегії вимірні на обгортці:
      талія  — припуск на талії помітно менший за припуск на грудях і на стегнах;
      колона — усі одягнені рівні тримаються у вузькій смузі припуску (рівна лінія).
    """
    if intent not in ПС.ФЛЕТЕРИНГ: return []
    р = ролі_зон(t)
    if р["ролі"].get("стегна") != "нейтральна": return []
    # ЗНАЙДЕНО НА ПРОГОНІ: гейт стояв тільки на нейтральній парі, а її мають і H, і X
    # (у обох плечі ≈ стегна). Тому X — тіло, у якого талія Є, — діставало вимогу,
    # адресовану H, і в нього відпадав `belted`, тобто його ж канонічний хід.
    # Вимога «створити талію або колону» стосується тіла, яке талії НЕ дає.
    # Для тіла з вираженою талією корпус вимагає протилежного: не сховати лінію.
    виражена = р["ролі"].get("талія") == "виражена"
    тал = _на(об, "талія", "припуск")
    гр = _на(об, "груди", "припуск"); ст = _на(об, "стегна", "припуск")
    if тал is None or гр is None or ст is None: return []
    втягнення = min(гр, ст) - тал
    # ВІСЬ КОЛОНИ — ШИРИНА КОНТУРУ (11.09.2026, наряд Н-V15-036). Доти тут стояв
    # розкид ПРИПУСКУ (ширина/ширина_тіла) по одягнених рівнях — і він міряв не
    # лінію одягу, а форму тіла під ним: припуск вибухає там, де тіло вузьке.
    # Наслідок був інверсією правила: широкі штани зі сталою шириною давали розкид
    # припуску 3.94 і колоною НЕ рахувались, а скіні по тілу — 0.12 і рахувались.
    # Це та сама помилка, яку файл уже виправив у `відльоти` (див. коментар там:
    # «око читає контур, а не відношення до тіла»), просто `нічия_стратегія` на нову
    # вісь не переведена. Сантиметри дизайн-припуску її не знімають (зміряно:
    # shift+straight 37.2 см проти 4.5 у bodycon+skinny) — інверсія в самій осі.
    ряд = [з for з in об if з["одягнено"]]
    ш = [з["ширина"] for з in ряд if з.get("ширина") is not None]
    сер = (sum(ш) / len(ш)) if ш else 0.0
    розкид_контуру = ((max(ш) - min(ш)) / сер) if сер else 0.0
    # Рівні, на яких стоїть вимір: груди/талія/стегна. Носій із дефолтним кроєм на
    # будь-якому з них переводить знахідку в питання (див. дефолтний_крій).
    заглушка = дефолтний_крій(об, ("груди", "талія", "стегна"))
    if виражена:
        # X: «слідувати лінії». Провал — коли одяг ЗАПОВНЮЄ талію: припуск на талії не
        # менший за припуск на грудях і стегнах, тобто вигин тіла зникає під річчю.
        if втягнення >= 0.0: return []
        return [_над_дефолтним_кроєм(_зн(
            "K-BOD-02", "strong",
            "боксі-крій ховає виражену талію",
            носії_рівнів(об, ("груди", "талія", "стегна")),
            # ЗНАЙДЕНО МОВНИМ ГЕЙТОМ НА ВЛАСНОМУ ВИХОДІ: тут у текст, що йде ЛЮДИНІ,
            # їхало сире WHR. Два окремі порушення в одному рядку:
            #   1) R-BPC-02 / R-LNG-01 — коментар про тіло числом. Показати людині
            #      «ваш WHR 0.70» — той самий жанр, що «вам краще L»: пояснення має
            #      триматись композиції, не метрики тіла.
            #   2) на цьому тілі WHR вийшов рівно 0.70, тобто текст ще й ЛУНАВ як
            #      фольклорний «ідеальний» коефіцієнт (R-ABC-13), якого система не
            #      має права ні стверджувати, ні натякати.
            # Число нікуди не зникло — воно поїхало в `діагностика`, яку читає розробник
            # і не читає людина.
            f"тіло дає виражену талію, але припуск на талії {тал} НЕ менший за "
            f"груди {гр} і стегна {ст} — вигин зникає під річчю (втягнення {втягнення:+.3f})",
            ремонт=["крій, що йде за лінією: приталений, запах, футляр, з поясом",
                    "АБО свідомо інша форма — але тоді це вибір, а не дефолт"],
            запит=dict(слот="верх", крій=["fitted", "wrap", "belted", "sheath", "bodycon"],
                       чому="K-BOD-02: не ховати виражену талію"),
            вимір=abs(втягнення), поріг=0.0, повна=C["втягнення_H"],
            ламається="міряється лише геометрія: талію видно й крізь прямий крій, якщо "
                      "тканина падає, а пояс носиться поверх — цього модуль не бачить",
            діагностика=dict(WHR=р["WHR"], перекос=р["перекос"],
                             нота="метрики тіла для розробника; у текст людині не йдуть "
                                  "(R-LNG-01, R-BPC-02)")), заглушка)]
    # `є_талія` НА ВІСЬ КОНТУРУ НЕ ПЕРЕВОДИТЬСЯ, І ЦЕ НАВМИСНО (крок 7 наряду).
    # Втягнення рахується на трьох ТОРСОВИХ рівнях (груди/талія/стегна), де тіло не
    # вужчає різко, тож відношення там нічого не спотворює: питання «чи одяг іде за
    # вигином» саме про відношення до тіла і є. Інверсія осі припуску живе там, де в
    # ряд потрапляють кінцівки — коліно, литка, щиколотка, — а їх тут нема.
    # Назване вголос, щоб наступна сесія не «полагодила» і це теж.
    є_талія = втягнення >= C["втягнення_H"]
    є_колона = розкид_контуру <= C["розкид_контуру_колони"]
    if є_талія or є_колона: return []
    return [_над_дефолтним_кроєм(_зн(
        "K-BOD-02", "strong",
        "ні талії, ні колони — «нічия» стратегія",
        носії_рівнів(об, ("груди", "талія", "стегна")),
        f"втягнення талії {втягнення:+.3f} при потрібних {C['втягнення_H']} "
        f"(припуск: груди {гр}, талія {тал}, стегна {ст}); розкид ширини контуру по "
        f"образу {розкид_контуру:.3f} (середня ширина {сер:.1f} см) при потрібних "
        f"≤{C['розкид_контуру_колони']} для читабельної колони. "
        f"Перекос балансної пари {р['перекос']:+.1%} — тіло не дає сигналу, тож форму "
        f"мусить задати одяг",
        ремонт=["створити талію: пояс, запах, баска, приталений крій",
                "АБО свідома колона: рівна лінія без перепадів (шифт, лонглайн-шар)"],
        запит=dict(слот="верх", крій=["belted", "wrap", "peplum", "fitted", "shift"],
                   чому="K-BOD-02: одна зі стратегій обов'язкова"),
        вимір=max(0.0, C["втягнення_H"] - втягнення), поріг=0.0,
        повна=C["втягнення_H"],
        ламається="дві стратегії взаємно виключні за побудовою тесту, а в реальному "
                  "образі бувають проміжні стани (легка талія + майже колона); поріг "
                  "втягнення не калібрований. Поріг колони теж T3: він узятий із "
                  "розриву між класами кроїв на синтетичній сітці, а не з розмічених "
                  "людиною образів — заміна осі зняла інверсію, вимірянішим правило "
                  "не стало"), заглушка)]


def конкуренція(t, об, intent="conventional"):
    """K-SIL-01: одна читабельна форма = один відліт контуру від тіла нижче плечей."""
    в = відльоти(об)
    if в["кількість"] < 2: return []
    точки = в["точки"]
    носії = sorted({т["носій"] for т in точки if т["носій"]})
    опис = "; ".join(f"«{т['рівень']}» {т['ширина']} см (вихід від «{т['від']}», "
                     f"виразність {т['виразність']}, від «{т['носій']}»)" for т in точки)
    слабша = min(точки, key=lambda т: т["виразність"])
    # СИЛА СТОЇТЬ НА РОЗДІЛЕННІ, НЕ НА ВИРАЗНОСТІ. Народження знахідки — це подія
    # «один пік розпався на два», і величина, що ПЕРЕТИНАЄ поріг у цю мить, — глибина
    # долини між ними. Виразність піка на цю мить уже далеко за порогом, тож на ній
    # правило народжувалось із силою 0.67 (див. реєстр, повна_розділення).
    най = (min(в["розділення"], key=lambda р: р["глибина"]) if в["розділення"] else None)
    опис_розд = ("; ".join(f"{р['між'][0]}↔{р['між'][1]} через «{р['долина']}» "
                           f"глибина {р['глибина']}" for р in в["розділення"])
                 or "долини не виміряні (відльоти не закриті контуром)")
    # РІВНІ ЗВУЖЕНІ до тих, на яких стоять відльоти: виразність рахується саме на
    # них (аналог `носії_рівнів`), тож заглушка на щиколотці не має права гасити
    # знахідку про два об'єми на грудях і стегнах.
    заглушка = дефолтний_крій(об, tuple(т["рівень"] for т in точки))
    return [_над_дефолтним_кроєм(_зн(
        "K-SIL-01", "strong",
        f"контур відходить від тіла у {в['кількість']} різних точках — одна лінія не читається",
        носії,
        f"відльоти: {опис}. Розділення (глибина долини між об'ємами): {опис_розд}. "
        f"Порогова виразність {C['виразність_відльоту']} ширини ТІЛА "
        f"(масштаб тіла {в['масштаб_тіла']} см; обгортка {в['середня_ширина']} см). "
        f"Контур згори вниз: {в['контур']}",
        ремонт=[f"прибрати слабший відліт на «{слабша['рівень']}»: замінити "
                f"«{слабша['носій']}» на прилеглий крій",
                "лишити один об'єм, другий слот вести по тілу"],
        запит=dict(слот=None, замість=слабша["носій"],
                   крій=["fitted", "sheath", "skinny", "pencil", "straight"],
                   чому=f"K-SIL-01: прибрати другий відліт на «{слабша['рівень']}»"),
        вимір=(най["глибина"] if най else слабша["виразність"]),
        поріг=C["виразність_відльоту"],
        повна=(C["повна_розділення"] if най else C["повна_відльоту"]),
        ламається="відліт міряється по фронтальному припуску: об'єм, що йде назад "
                  "(турнюр, кокон), не рахується. Рукав у профілі не бере участі — "
                  "а рукав-ліхтарик це теж відліт, просто в іншій площині. Розділення "
                  "не виміряне, коли нижній відліт доходить до поділу й не має спаду: "
                  "тоді сила падає назад на виразність і розрив на межі вертається",
        примітка=None if intent in ПС.ФЛЕТЕРИНГ else
                 "за fashion-forward кілька відльотів — свідома конструкція"), заглушка)]
