def розведеність_масштабу(m_a, m_b):
    """ЄДИНЕ місце, де живе конвенція «розводити масштаб принтів ≥2×» (майже
    одностайна згода практиків). 1.0 = добре розведені, 0.0 = конкурують.

    ЄДИНИЙ СПОЖИВАЧ цього числа — K-COL-10 нижче (`принти`, рядки з `розведеність_масштабу`:
    найгірша пара в міксі й окрема знахідка «близького масштабу»). palette.мікс_принтів
    віддавав ТУ САМУ механіку під ID P-PRT-05 і тим самим реченням: число було винесене
    сюди, а РІШЕННЯ, що на ньому стоїть, — ні. Саме так дублі й виникають: екстракція
    спиняється на константі.

    І ВГОЛОС (Н-V16-041, виміряно 12.09.2026): «єдиний емітент» тут стояло неправдою —
    єдиний тут СПОЖИВАЧ числа, а сам ID K-COL-10 має ще двох виробників виходу:
      · `pipeline._доповнення_судді` — знахідка з НАЗВИ речі, коли поля `візерунок`
        у каталозі нема (регекси ПРИНТИ: леопард/смужка/клітинка/квіти/горох);
      · `palettes.прийоми` — цитата джерела від завжди-активного прийому «принт»
        (K-PAL-10), напрям «цитата джерела», слідом не рахується.
    None, коли масштаб хоч однієї речі не виміряний — тоді правило не вдає, що знає.
    Вимір дає feed._просторові_міри (масштаб_відн); поріг 2× — T3 некалібрований."""
    if m_a is None or m_b is None:
        return None
    від = max(m_a, m_b) / max(1e-6, min(m_a, m_b))
    return round(min(1.0, max(0.0, (від - 1.0) / 1.0)), 2)   # 1×→0.0, 2×+→1.0

# ── R-PRN-04 · форма мотиву (крива/кутова) — виводиться з КЛАСУ ─────────────
# Корпус: «відлуння форми — криві мотиви з кривими, кутові з кутовими — м'який
# бонус когерентності» (hint). Форма класу — майже механічна геометрія (горох
# круглий, смуга пряма), але межові класи (камуфляж=органічні плями) — конвенція;
# абстрактний і generic «принт» форми не мають і в мапі відсутні свідомо.
ФОРМА_МОТИВУ = {"горох": "крива", "квітковий": "крива", "пейслі": "крива",
                "анімалістичний": "крива", "камуфляж": "крива",
                "смужка": "кутова", "клітинка": "кутова", "геометричний": "кутова"}

def принти(речі, E):
    """K-COL-10. Мікс принтів тримається на спільній колірній нитці.
    ВИПРАВЛЕНО ПІСЛЯ ПРОБИ: правило судило ВСІ речі образу, зокрема ті, яких у цьому
    стані не видно. Під застібнутим пальтом смугастий топ невидимий, а «мікс принтів
    без спільного кольору» все одно спрацьовував — вердикт про те, чого ніхто не бачить.

    ДОДАНО, КОЛИ МАСШТАБ СТАВ ВИМІРНИМ: раніше тут стояло «масштаб не вимірюється —
    це вхід від VLM, якого модуль не має», а сила була плоска strong. Тепер, якщо
    речі несуть поле `масштаб_відн` (з feed.палітра_принту), сила НЕПЕРЕРВНО спадає
    з розведеністю масштабів — рівно те, що казало власне `ламається` цього правила.
    І симетрично: близькі масштаби дають окрему знахідку навіть за спільної нитки."""
    видимі_id = {e["річ"] for e in E}
    # None-ФІКС (фейл-кейс ager 24.08.2026): каталог фіду кладе ключ `візерунок`
    # ЗАВЖДИ, зокрема зі значенням None («назва мовчить»). `.get(..., "solid")`
    # дефолт не вмикав, None проходив `!= "solid"` — і ДВІ ЯВНО ОДНОТОННІ речі
    # («Кардиган однотонный» + «Штаны однотонные») діставали K-COL-10 strong
    # «мікс принтів». Мовчання назви ≠ принт: невідоме не бере участі в міксі.
    p = [r for r in речі
         if (r.get("візерунок") or "solid") != "solid" and r["id"] in видимі_id]
    зн = []
    # ── R-PRN-09 · камуфляж/мілітарі — культурний гейт (не мікс, тому до len<2) ──
    for r in [x for x in речі if x.get("візерунок") == "камуфляж" and x["id"] in видимі_id]:
        # ── ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026) ────────────────
        # before: «камуфляжний мотив у воєнному контексті» — рядок не називав РЕЧІ
        # (у образі камуфляж може бути на штанях, на куртці, на хустці) і не казав,
        # що з ним робити. Напрям стояв у `ремонт` («свідомий вибір лишити») і в
        # `ламається` («позначка, не заборона») — обидва поля до промпту ші не
        # доїжджають, тож вона діставала докір без адресата й без дії.
        # after (два справжні рядки з двох прогонів):
        #   · «штани камуфляж»: камуфляж у воєнному контексті читається як позиція
        #     — лишати свідомо [0.25]
        #   · «куртка камуфляжна»: камуфляж у воєнному контексті читається як
        #     позиція — лишати свідомо [0.25]
        # Річ — це `r["id"]` того самого циклу; «лишати свідомо» переписане дослівно
        # з `ремонт` цього ж виклику, нічого не дораховано.
        зн.append(dict(_зн("R-PRN-09", "hint",
            "«%s»: камуфляж у воєнному контексті читається як позиція — лишати свідомо"
            % r["id"],
            [r["id"]],
            "камуфляж/мілітарі в UA-каталозі культурно навантажений — не нейтральний "
            "патерн (корпус: аналогів у зовнішніх джерелах нема, правило існує, бо "
            "цього вимагає ринок)",
            ремонт="свідомий вибір лишити; сама знахідка лише називає навантаження",
            ламається="поза воєнним/UA-контекстом правило не діє; сила hint до "
                      "польової перевірки — це позначка, не заборона"),
            сила_нп=0.25, сила_нп_джерело="hint: корпусна сила, польової перевірки нема"))
    # ── R-PRN-03 · та сама сім'я мотиву — НЕ «мікс» (фейл-кейс горох+горох) ─────
    # ДО: пара «Свитшот в горох» + «Штаны в горох» судилась K-COL-10 strong «мікс
    # без спільного кольору». Корпус для same-family питає інше: розрив масштабу
    # ≥×2 І різницю value/chroma/texture — ОБИДВІ умови. Ниткою тут є сам мотив.
    іменовані = [r for r in p if r.get("візерунок") not in (None, "принт")]
    сім_класи = {}
    for r in іменовані: сім_класи.setdefault(r["візерунок"], []).append(r)
    same_ids = set()
    for клас, група in сім_класи.items():
        if len(група) < 2: continue
        same_ids |= {r["id"] for r in група}
        пари = [(a, b) for i, a in enumerate(група) for b in група[i+1:]]
        for a, b in пари:
            розв = розведеність_масштабу(a.get("масштаб_відн"), b.get("масштаб_відн"))
            if розв is None:
                зн.append(dict(_зн("R-PRN-03", "питання",
                    "одна сім'я мотиву — умова ×2 неперевірна",
                    sorted([a["id"], b["id"]]),
                    "обидві речі несуть «%s» (клас зі слова назви); корпус вимагає "
                    "розрив масштабу ≥×2 І різницю значення/хроми/фактури, а масштаб "
                    "не виміряний — фото недосяжні" % клас,
                    ремонт="узяти версії помітно різного масштабу мотиву або розвести "
                           "світлотою; або лишити свідомо — той самий мотив у двох "
                           "колорвеях працює",
                    ламається="за виміряним масштабом питання зникає: умова стає "
                              "перевірною і судиться нижньою гілкою"),
                    сила_нп=0.4,
                    сила_нп_джерело="питання: вхід (масштаб) відсутній, не вимір"))
                continue
            La, Lb = a["colors"][0]["lab"][0] if a.get("colors") else None, \
                     b["colors"][0]["lab"][0] if b.get("colors") else None
            # поріг різниці значення: 10 L* — T3 ФОЛЬКЛОРНА КОНСТАНТА (корпус числа
            # не дає, «difference in value» без величини); позначено, не приховано
            різн_L = (La is not None and Lb is not None and abs(La - Lb) >= 10.0)
            if not (розв >= 1.0 and різн_L):
                зн.append(dict(_зн("R-PRN-03", "soft",
                    "одна сім'я мотиву без розведення",
                    sorted([a["id"], b["id"]]),
                    "клас «%s» двічі: розведеність масштабу %.2f (1.0 ≈ ×2), "
                    "різниця значення %s — корпус вимагає ОБИДВІ умови, інакше це "
                    "частотний конфлікт" % (клас, розв,
                        "є" if різн_L else "нема"),
                    ремонт="узяти один мотив ≥×2 дрібнішим/більшим І розвести "
                           "світлотою або фактурою",
                    ламається="той самий принт у двох колорвеях — легітимний прийом; "
                              "поріг ×2 і 10 L* — некалібровані конвенції практиків",
                    поріг=2.0),
                    сила_нп=round(max(0.0, 1.0 - 0.5*розв - (0.3 if різн_L else 0.0)), 2),
                    сила_нп_джерело="вимір (розведеність) + T3-поріг різниці L"))
    if len(p) < 2: return зн
    # ЧИСТА ОДНА СІМ'Я (усі принти образу — один іменований клас) — не «мікс»:
    # питання про неї вже поставив R-PRN-03 вище; K-COL-10 «без спільного кольору»
    # тут давав хибний strong, бо словесний шар кольору знає лише основний колір
    # речі й не бачить спільного ґрунту/горошин (фейл-кейс горох+горох 24.08.2026)
    _класи_p = {r.get("візерунок") for r in p}
    if len(_класи_p) == 1 and "принт" not in _класи_p:
        return зн
    # ── R-PRN-04 · відлуння форми: криві з кривими, кутові з кутовими ────────
    # Лише РІЗНІ іменовані сім'ї (та сама сім'я тривіально відлунює — R-PRN-03).
    # Бонус, не проблема: hint-репліка називає когерентність, нічого не блокує.
    for _форма in ("крива", "кутова"):
        _чл = [r for r in p if ФОРМА_МОТИВУ.get(r.get("візерунок")) == _форма]
        _сімей = {r["візерунок"] for r in _чл}
        if len(_чл) >= 2 and len(_сімей) >= 2:
            # ── ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026) ────────────
            # before: «відлуння форми між принтами» — однаковий рядок і для пари
            # горох+квітковий, і для смужка+клітинка, тобто ші не бачила ні ЯКОЇ
            # форми відлуння, ні ЯКІ речі його тримають, ні що з цим робити.
            # Це БОНУС, і саме тому старий рядок був найбезпораднішим: зауваження
            # ші хоч лагодить, а безадресну похвалу вона нічим не може врахувати —
            # «м'який бонус когерентності» жив у `чому`, який до промпту не їде.
            # after (два справжні рядки з одного прогону):
            #   · криві мотиви (горох, квітковий) відлунюють формою — мікс
            #     тримається на цьому, лишити [0.20]
            #   · кутові мотиви (клітинка, смужка) відлунюють формою — мікс
            #     тримається на цьому, лишити [0.20]
            # Форма й сім'ї беруться з `_форма`/`_сімей`, уже обчислених цим циклом;
            # «лишити» — це дослівно те, що каже `ламається` («бонус, не вимога»).
            зн.append(dict(_зн("R-PRN-04", "hint",
                "%s мотиви (%s) відлунюють формою — мікс тримається на цьому, лишити"
                % (_форма.replace("крива", "криві").replace("кутова", "кутові"),
                   ", ".join(sorted(_сімей))),
                sorted(r["id"] for r in _чл),
                "%s мотиви різних сімей (%s) — форма відлунює, м'який бонус "
                "когерентності міксу" % (_форма.replace("крива", "криві")
                                         .replace("кутова", "кутові"),
                                         ", ".join(sorted(_сімей))),
                ламається="бонус, не вимога: мікс без відлуння форми легітимний; "
                          "форма межових класів — конвенція, не вимір"),
                сила_нп=0.2, сила_нп_джерело="hint: форма з класу мотиву (слово)"))
    ids = {r["id"] for r in p}
    сім = {i: {e["сім_я"] for e in E if e["річ"] == i} for i in ids}
    спільні = set.intersection(*сім.values()) if сім else set()
    # розведеність за найбільшою парою (найгірший випадок конкуренції);
    # same-family пари вилучені — їхню конкуренцію масштабів судить R-PRN-03
    _кл = {r["id"]: r.get("візерунок") for r in p}
    масштаби = [(r["id"], r.get("масштаб_відн")) for r in p]
    пари = [(a, b) for i, a in enumerate(масштаби) for b in масштаби[i+1:]
            if not (_кл[a[0]] == _кл[b[0]] and _кл[a[0]] != "принт")]
    розв = [(a[0], b[0], розведеність_масштабу(a[1], b[1])) for a, b in пари]
    виміряні = [x for x in розв if x[2] is not None]
    гірша = min(виміряні, key=lambda x: x[2]) if виміряні else None
    if not спільні:
        # база strong; виміряна розведеність масштабів послаблює неперервно
        сила_нп = 1.0 if гірша is None else round(1.0 - 0.6*гірша[2], 2)
        кат = "strong" if сила_нп >= 0.7 else ("soft" if сила_нп >= 0.45 else "hint")
        чому = "без спільної нитки мікс розпадається на дві окремі речі"
        if гірша is not None:
            чому += "; масштаби розведено на %.2f (1=добре) — це частково рятує" % гірша[2]
        зн.append(dict(_зн("K-COL-10", кат, "мікс принтів без спільного кольору",
            sorted(ids), чому,
            ремонт="замінити один принт на версію, що містить колір другого, АБО зв'язати "
                   "третьою річчю у спільному кольорі",
            запит=dict(слот="шарф|сумка|взуття", сім_я="колір другого принту",
                       чому="спільна нитка для міксу"),
            ламається="чітке домінування одного принту за площею рятує навіть без нитки; "
                      + ("масштаб узято з виміру фото речі (відносно кадру, не в см)"
                         if гірша is not None else
                         "масштаб не виміряний для цих речей — сила не послаблена")),
            сила_нп=сила_нп))
    if гірша is not None and гірша[2] < 0.5:
        сила_нп = round(1.0 - 2*гірша[2], 2)          # 0 розведеності -> 1.0, 0.5 -> 0.0
        зн.append(dict(_зн("K-COL-10", "hint" if сила_нп < C["нп_межа_soft"] else "soft",
            "два принти близького масштабу конкурують", sorted([гірша[0], гірша[1]]),
            "розведеність %.2f: мотиви одного калібру сперечаються за увагу" % гірша[2],
            ремонт="узяти один принт помітно дрібнішим або більшим; спільний колір лишити",
            ламається="однаковий масштаб працює, коли це той самий принт у двох колорвеях "
                      "або коли другий принт мікроскопічний за площею",
            поріг=2.0), сила_нп=сила_нп, сила_нп_джерело='вимір (власний: розведеність масштабу)'))
    return зн
