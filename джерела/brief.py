def смуги_краю(T, крок=1.0):
    """Висоти від підлоги, де край виробу лягає на опуклість тіла І є куди його
    зсунути. Це головне, що код може сказати, а текст правила — ні: «не на
    найширшій точці» без тіла нічого не означає, з тілом це «не 44–49 см»."""
    проф = T["профіль"]; зріст = T["зріст"]
    погані, поч = [], None
    y = 2.0
    while y <= зріст - 2.0:
        м = ПС.край_проти_локального(проф, y)
        зле = м["на_максимумі"] and м["важіль_є"]
        if зле and поч is None: поч = y
        if not зле and поч is not None:
            if y - крок - поч >= 1.5: погані.append((round(поч), round(y - крок)))
            поч = None
        y += крок
    if поч is not None and зріст - поч >= 1.5: погані.append((round(поч), round(зріст)))
    return погані


