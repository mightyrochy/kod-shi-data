def запит_B(сценарій_текст, блок, вимоги="", без_фото=False, формат=None, колір=""):
    """Вимоги людини стоять ПІСЛЯ умов і мають над ними старшинство.

    СПІЙМАНО РЕАЛЬНИМ ПРОГОНОМ: тестувальниця написала «тонкі підбори», а в
    умовах стояло «без шпильок, стійка підошва» (вето під рух) і «тонкий каблук
    під широку штанину заборонений». Правило мовчки перемогло людину, і прохання
    зникло без сліду. Це неприйнятно: правила існують, щоб служити людині, а не
    щоб її переважувати. Тепер вимоги йдуть останніми — модель читає їх після
    умов — і несуть явну вказівку про пріоритет."""
    if isinstance(блок, dict):
        блок = блок["текст"]
    хвіст = ""
    if (вимоги or "").strip():
        хвіст = (f"{_вимоги(вимоги)}\n"
                 "Якщо якась із умов вище суперечить цим вимогам — виконуй вимоги "
                 "людини, а умову порушуй свідомо й скажи в тексті окремим рядком "
                 "«СВІДОМО: <річ> — <чому>» (саме так, бо цей рядок читає код).")
    зав, фор = (ЗАВДАННЯ_БЕЗ_ФОТО, ФОРМАТ_ЛИШЕ_ТЕКСТ) if без_фото else (ЗАВДАННЯ, ФОРМАТ)
    # ── ДВІ ІНСТРУКЦІЇ ФОРМАТУ В ОДНОМУ ПРОМПТІ — ЦЕ ЗАВЖДИ ПОМИЛКА ───────────
    # СПІЙМАНО ПРОГОНОМ, НЕ ЧИТАННЯМ (30.08.2026): щойно пакет каталогу почав
    # просити N образів «БЕЗ будь-якої іншої прози», у промпті руки B стало ДВА
    # формати — пакетний у середині й цей прозовий в кінці («1. Речі — по рядку…
    # 3. Чому це працює — 3–4 речення»). Останній виграє за свіжістю, тобто
    # замовлення десяти образів мовчки поверталось одним описом, і розбір
    # `образи_з_тексту` знаходив один рядок замість десяти. Ззовні це виглядало б
    # як «модель не послухалась», а насправді її просили про протилежне.
    # `формат=""` — явне зняття хвоста тим, хто вже несе свій формат.
    if формат is not None:
        фор = формат
        # ЗАВДАННЯ НЕ СУПЕРЕЧИТЬ ФОРМАТУ (02.09.2026). Хвіст знято, а перший
        # рядок і далі казав «Склади ОДИН образ» — і в кінці того самого промпта
        # стояло «Дай 10 РІЗНИХ образів». Модель читає обидва; який переможе —
        # лотерея свіжості. Коли формат несе пакет, завдання каже це прямо.
        if формат == "":
            зав = зав.replace("Склади ОДИН образ під випадок нижче.",
                              "Склади образи під випадок нижче — скільки і в якому форматі, сказано в кінці.")
    # КОЛІР ЛЮДИНИ СТОЇТЬ ПЕРЕД УМОВАМИ КОДУ, А НЕ ВСЕРЕДИНІ НИХ. У блоці умов
    # він жив лише як hex у рядках слотів («верх: #4d403f»); слова «вона обрала
    # червоний» не було в жодній руці. Тепер речення однакове в усіх чотирьох —
    # різняться руки схемою й каталогом, не бажанням людини.
    к = (колір + "\n\n") if колір else ""
    return (f"{зав}\n\nВИПАДОК\n{сценарій_текст}\n\n{к}"
            f"УМОВИ — виміряні з фото й мірок цієї людини, дотримуйся їх усіх\n{блок}"
            f"{хвіст}" + (f"\n\n{фор}" if фор else ""))


