# ── кольори з вікна ─────────────────────────────────────────────────
def _hex(L, C, h):
    c = min(C, cs.c_max(L, h))
    a, b = c * math.cos(math.radians(h)), c * math.sin(math.radians(h))
    r, g, bl = cs.to_rgb(L, a, b)
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v * 255))) for v in (r, g, bl))


def _дуга_середина(дуга):
    """Середина дуги з урахуванням переходу через 0°."""
    a, b = float(дуга[0]) % 360, float(дуга[1]) % 360
    if b < a:
        b += 360.0
    return ((a + b) / 2.0) % 360.0


