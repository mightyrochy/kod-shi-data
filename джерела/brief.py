def крок_світлоти(gap):
    """Скільки одиниць світлоти може розділяти найсвітлішу й найтемнішу річ.

    БУЛО СХОДИНКОЮ, І ЦЕ ЛОВИЛОСЬ ПРОГОНОМ. Крок брався по РІВНЮ контрасту:
    низький→25, середній→45, високий→100. Рівень — три відра з порогами 22/45,
    тому людина з щілиною 44.9 діставала 45 одиниць, а з 45.1 — сто. Різниця
    вдвічі з нічого. На прогоні похибка заміру шкіри ±3 L* перекидала рівень на
    двох профілях із трьох — тобто крок у брифі вирішувала точка на щоці, а не
    людина. Це рівно та бакетизація, яку аудит неперервності забороняє правилам.

    СТАЛО НЕПЕРЕРВНИМ, БЕЗ НОВИХ КОНСТАНТ. Ті самі три числа лишаються, але як
    ЯКОРІ, між якими йде пряма: центр низького (11), поріг 22/45 → середина
    середнього (33.5), і 45+ як початок високого. Порогів 22/45 не чіпаю — вони
    T3 і живуть в одному місці (outfit.РІВНІ_КОНТРАСТУ). Змінилась лише форма
    переходу: замість стрибка — нахил. Сила не зросла: 25/45/100 як були
    фольклорними, так і лишились, просто більше не роблять із похибки виміру
    двократну різницю в брифі."""
    lo, hi = 22.0, 45.0                      # = outfit.РІВНІ_КОНТРАСТУ
    якорі = ((0.0, 25.0), (lo, 25.0), ((lo + hi) / 2, 45.0), (hi, 70.0), (100.0, 100.0))
    g = max(0.0, min(100.0, float(gap)))
    for (x0, y0), (x1, y1) in zip(якорі, якорі[1:]):
        if g <= x1:
            return round(y0 + (y1 - y0) * (g - x0) / (x1 - x0))
    return 100


