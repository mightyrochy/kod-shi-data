def перефарбувати_L(hex_, ціль_L):
    """Той самий колір на іншій світлоті: рухається L*, a* і b* лишаються.

    Потрібне донору (рука C) для макіяжу. Тон НЕ чіпається навмисно: правило
    читає саме тон, і його підміна зробила б донора не «іншою людиною», а
    неможливою — а плацебо мусить бути правдоподібним, інакше суддя впізнає
    його за абсурдом і тест міряє уважність замість правил.

    ⚠ ТОН ВСЕ Ж ТРОХИ ЇДЕ, і це виміряно, а не проігноровано: на краях шкали
    sRGB не тримає (a*, b*) при новій світлоті, і зворотна конверсія обрізає.
    На пробі #6e1f2e (L*25.2, h 16.0°) донор із L*9.8 дав h 23.5° — зсув 7.5°.
    Це менше за найвужчу дугу відношень (12°), тож рід дуги не міняється; але
    якщо колись знадобиться точний тон донора, конвертувати треба з утриманням
    тону, а не компонент."""
    import colorspace as _cs
    L, a, b = _cs.hx(hex_)
    L2 = max(4.0, min(96.0, float(ціль_L)))
    r, g, bb = _cs.to_rgb(L2, a, b)
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v * 255)))
                                   for v in (r, g, bb))


def донор(lab_шкіри, lab_волосся, lab_очей, зріст, обхвати):
    """Інша людина, побудована з цієї детермінованим вивертанням: контраст
    перекидається на протилежний кінець шкали, фігура — на протилежний тип.

    Нагода НЕ чіпається: вона не правило, а переказ вводу. Якби вона різнилась,
    суддя впізнав би плацебо за невідповідністю випадку, і тест міряв би
    уважність, а не правила. B і C різняться рівно тим, що код каже ПРО ЛЮДИНУ.

    ПЕРША ВЕРСІЯ ЦЬОГО НЕ РОБИЛА НІЧОГО: вона міняла місцями світлоти шкіри й
    волосся, а |81.6−59.9| однакове в обидва боки — плацебо виходило дослівною
    копією B (10 спільних рядків з 11). Тому зсув задавався за модулем.

    ДРУГА ВЕРСІЯ ЛАМАЛАСЬ НА КРАЮ ШКАЛИ, і це спіймав реальний прогін
    (лог_1.json): шкіра L*89.0, волосся L*93.2, щілина 4.2. Напрям обирався за
    знаком (волосся світліше → зсувати вгору), 89.0 + 58 = 147 упиралось у стелю
    94.0, і донор виходив зі щілиною 5.0 замість перекинутої. Розбіжність брифів
    0.25 при порозі 0.4 — рука C була майже копією B, тобто сліпий тест на цьому
    прогоні не міряв нічого. Тепер напрям обирається за МІСЦЕМ на шкалі, а не за
    знаком поточної різниці: до якого кінця є куди йти від шкіри, туди й ідемо.
    """
    Lш = lab_шкіри[0]; Lв = lab_волосся[0]
    щілина = abs(Lш - Lв)
    if щілина < МЕЖА_КОНТРАСТУ:
        # особа низькоконтрастна → донор мусить бути висококонтрастним:
        # волосся на протилежний від шкіри кінець шкали (там і є весь запас)
        Lв2 = 8.0 if Lш >= 50 else 92.0
    else:
        # висококонтрастна → донор низькоконтрастний: волосся впритул до шкіри
        Lв2 = Lш + (10.0 if Lш < 50 else -10.0)
    Lв2 = max(6.0, min(94.0, Lв2))
    lab_в2 = (Lв2, lab_волосся[1], lab_волосся[2])

    об = dict(обхвати)
    пл, ст = float(об.get("плечі", 100)), float(об.get("стегна", 100))
    сер = (пл + ст) / 2.0
    різ = abs(пл - ст)
    крок = max(10.0, різ + 8.0)                   # гарантовано інший тип корпусу
    if пл >= ст:  об["плечі"], об["стегна"] = round(сер - крок/2, 1), round(сер + крок/2, 1)
    else:         об["плечі"], об["стегна"] = round(сер + крок/2, 1), round(сер - крок/2, 1)
    об["талія"] = round(min(об["плечі"], об["стегна"]) * 0.78, 1)
    if "груди" in об: об["груди"] = round((об["плечі"] + об["талія"]) / 2, 1)
    return lab_шкіри, lab_в2, lab_очей, об


def перевірити_плацебо(бриф_B, бриф_C):
    """Скільки рядків плацебо реально відрізняється. Якщо мало — абляція не
    міряє нічого, і це має бути видно, а не сховане."""
    tB = бриф_B["текст"] if isinstance(бриф_B, dict) else бриф_B
    tC = бриф_C["текст"] if isinstance(бриф_C, dict) else бриф_C
    b = [x for x in tB.split("\n") if x.strip()]
    c = [x for x in tC.split("\n") if x.strip()]
    спільних = len(set(b) & set(c))
    return dict(рядків=len(b), спільних=спільних,
                розбіжність=round(1 - спільних / max(1, len(b)), 3),
                придатне=(1 - спільних / max(1, len(b))) >= 0.4)
