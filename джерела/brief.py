def _орієнтир(H, a, b=None):
    """Найближчий орієнтир тіла до висоти від підлоги. Модель не має лінійки."""
    y = (a + (b if b is not None else a)) / 2.0
    точки = []
    for назва, ключ in ОРІЄНТИРИ:
        if ключ and ключ in H:
            точки.append((abs(H[ключ] - y), назва))
    if "стегна" in H and "талія" in H:
        точки.append((abs((H["стегна"] + H["коліно"]) / 2 - y), "середині стегна"))
        точки.append((abs((H["талія"] + H["груди"]) / 2 - y), "під грудьми"))
    точки.sort()
    return точки[0][1] if точки else f"на {round(y)} см від підлоги"


