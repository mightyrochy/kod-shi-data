def колір_слота(v, запас_h=30.0):
    """ОДИН конкретний колір слота. Тон — із дуги, яку задала схема; якщо схема
    тон не обмежує (нейтральна роль або нема якоря), береться запасний кут і це
    чесно позначається в тексті як «тон вільний»."""
    L = (v["L"][0] + v["L"][1]) / 2.0
    C = (v["C"][0] + v["C"][1]) / 2.0
    дуга = v.get("дуга_тону")
    вільний = дуга is None
    h = запас_h if вільний else _дуга_середина(дуга)
    if v.get("сім_я"):                       # нейтраль: хрома притиснута
        C = min(C, 10.0)
    # НАСИЧЕНІСТЬ — ВИБІР ЛЮДИНИ, НЕ ВИМІР. Скарга з прогону: «чому всі кольори
    # приглушені». Бо вікно C* задає схема під контраст особи, а людину ніхто не
    # питав. Множник рухає лише хрому емітованого кольору; тон і світлота, які
    # несуть правила, лишаються на місці.
    C *= float(v.get("_насиченість") or 1.0)
    C = max(0.0, min(C, 90.0))
    return _hex(L, C, h), вільний


