    # не має права їхати як «вона обрала»: це різні твердження (див. бриф.бриф).
    якщо_дефолт = (вибір or {}).get("база_за_замовчуванням")
    хто = "код запропонував і вона не міняла" if якщо_дефолт else "вона обрала сама"
    return ("ОСНОВНИЙ КОЛІР ОБРАЗУ: %s%s — %s. Образ будується навколо нього."
            % (слово, (" (%s)" % hx) if hx else "", хто))


