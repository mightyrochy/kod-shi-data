УСІ_КОДИ = tuple(sorted({к for з in ПЕРЕЛІК for к in з["коди"]}))


def дія_правил(тінь_пулу=(), ключі_брифа=(), перелік=ПЕРЕЛІК):
    """{ід: [місця]} — де кожне правило переліку ДІЄ на цьому прогоні руки 1.

    `тінь_пулу` — тінь пакета руки 1 під стеженням за `УСІ_КОДИ` (місця pool, witness,
    prompt пакета); `ключі_брифа` — коди рядків брифа руки 1 (`бриф["правила"][].код`).
    Свідок (`witness`, R-COL-16) — дія в пулі: він переставляє ранг основ і ключ сортування.
    Рядок задачі складання, що належить правилу (`пакет_моделі.РЯДКИ_ЗАДАЧІ_ЗА_ПРАВИЛОМ`), —
    дія в промпті. Правила, що діють лише в суді, тут не видно: суд бачить образ, а образу
    до відповіді моделі нема."""
    import пакет_моделі as _ПМ
    кл = set(ключі_брифа or ())
    вих = {}
    for з in перелік:
        наб = frozenset(з["коди"])
        м = {("pool" if т.get("де") == "witness" else т.get("де")) for т in (тінь_пулу or ())
             if _у(т.get("правило"), наб)}
        if кл & set(ключі_брифа_для(з["коди"])) or наб & set(_ПМ.РЯДКИ_ЗАДАЧІ_ЗА_ПРАВИЛОМ):
            м.add("prompt")
        м.discard(None)
        if м:
            вих[з["ід"]] = sorted(м)
    return вих


def _речі_пулу(пак):
    """Речі пулу пакета: {(слот, назва, ціна)}; None — пулу нема (прогін без каталогу)."""
    пул = ((пак or {}).get("пакет") or {}).get("пул")
    if not isinstance(пул, dict):
        return None
    return {(сл, р.get("назва"), р.get("ціна")) for сл, рр in пул.items() for р in (рр or [])}


def різниця_пулів(пак_1, пак_2):
    """Скільки речей пулу руки 2 нема в пулі руки 1 і навпаки (речі — слот, назва, ціна).

    Тінь каже, що правило ТОРКНУЛОСЬ пулу; ця лічба — чи пул від того став іншим. Рядок
    металу палітри (K-PAL-11) торкається пулу щоразу, а речей міняє одну-дві з 400, і
    заглушка стенда, що бере k-ту річ кожного слота, складає тоді той самий образ.
    None — пулу нема (прогін без каталогу)."""
    а, б = _речі_пулу(пак_1), _речі_пулу(пак_2)
    return None if а is None or б is None else len(а ^ б)


def різниця_по_слотах(пак_1, пак_2):
    """Ті самі речі, що в `різниця_пулів`, але по слотах: {слот: скільки} лише слоти, де пул руки 2
    різниться (Р2-2г, рядок 434: звіт пари каже, КУДИ правило пулу зсунуло добір, а не лише скільки).
    Порожній словник — пули збігаються; None — пулу нема."""
    а, б = _речі_пулу(пак_1), _речі_пулу(пак_2)
    if а is None or б is None:
        return None
    вих = {}
    for сл, _, _ in (а ^ б):
        вих[сл] = вих.get(сл, 0) + 1
    return dict(sorted(вих.items()))


def слоти_рядком(різниця):
    """Різницю по слотах кодовим рядком звіту: «слот:n,слот:n»; none — пули збігаються; None → None."""
    return None if різниця is None else (",".join("%s:%d" % (сл, n) for сл, n in різниця.items()) or "none")


def різниця_промптів(пак_1, пак_2):
    """Чи текст пакета руки 2 інший за текст пакета руки 1 (Р2-2д, рядок 641): True | False;
    None — одного з пакетів нема (прогін без каталогу). Пакет несе і пул, і рядки брифа, і
    `coat_required`, тож різниця тут — це все, що правило змінило у вході моделі."""
    а, б = [(п or {}).get("текст") for п in (пак_1, пак_2)]
    return None if not (isinstance(а, str) and isinstance(б, str) and а and б) else а != б


def ярус_виміряно(пара, пул_різниця, промпт_різний, місця):
    """Ярус пари ЗА ВИМІРЯНИМ входом руки 2 (Р2-2д, рядок 641), а не за тінню: `pool` — пул руки 2
    справді інший; `prompt_only` — пул той самий, інший пакет (`coat_required`, рядок брифа);
    `judge` — вхід моделі той самий, різниця може бути лише в суді. `дія_тінь` — що казала тінь
    жеребу (правило ТОРКАЄТЬСЯ пулу ≠ пул змінився). Нічого не виміряно (нема каталогу) або пара
    порожня з жеребу — без змін."""
    п = dict(пара or {})
    if п.get("дія") == "empty" or (пул_різниця is None and промпт_різний is None):
        return п
    п["дія_тінь"] = п.get("дія")
    if пул_різниця:
        п["дія"] = "pool"
    elif промпт_різний:
        п["дія"] = "prompt_only"
    elif "judge" in (місця or ()):
        п["дія"] = "judge"
    else:
        п["дія"], п["чому"] = "empty", "pool_prompt: measured_no_input_diff"
    return п


def виміряти_пару(поломка, пак_1, пак_2, частин=(1, 1)):
    """Одним місцем для `запити` і `від_моделі` (Р2-2д, рядки 431, 640, 641): що правило змінило
    у вході руки 2 порівняно з рукою 1 — полями `поломка` й кодовим рядком журналу `що_змінено`.

    Поля рядка: `pool_diff`, `pool_diff_slots` (як доти); `prompt_diff` (пакет інший: 1|0|unknown);
    `input_diff` = none | pool | prompt | pool+prompt | unknown; `pair_measures` — що міряє пара:
    при `input_diff=none` рука 2 складена з того самого пулу й промпту (правило лише суду, рядок
    640), тож картки різняться шумом моделі плюс судом; `parts` = частин пулу руки 1 / руки 2
    (рядок 431: з `частин` > 1 пул руки 1 збирається на кілька бюджетів, а рука 2 на один).
    `pair=` у рядку переписано виміряним ярусом; жеребова тінь лишилась у `пара.дія_тінь`."""
    пул, слоти, пром = різниця_пулів(пак_1, пак_2), різниця_по_слотах(пак_1, пак_2), різниця_промптів(пак_1, пак_2)
    поломка.update(пул_різниця=пул, пул_різниця_слоти=слоти, промпт_різниця=пром)
    поломка["пара"] = ярус_виміряно(поломка.get("пара"), пул, пром, поломка.get("місця"))
    п = поломка["пара"]
    зм = [] if пул is None and пром is None else [("pool" if пул else None), ("prompt" if пром else None)]
    вхід = "unknown" if пул is None and пром is None else ("+".join(х for х in зм if х) or "none")
    хвіст = ["pool_diff=%s" % пул, "pool_diff_slots=%s" % слоти_рядком(слоти),
             "prompt_diff=%s" % ("unknown" if пром is None else int(пром)), "input_diff=" + вхід,
             "pair_measures=" + {"none": "judge+model_noise", "unknown": "unknown"}.get(вхід, "input+judge+model_noise"),
             "parts=%d/%d" % tuple(частин)]
    сегм = [("pair=%s%s" % (п.get("дія") or "unknown", (":" + п["чому"]) if п.get("чому") else ""))
            if с.startswith("pair=") else с for с in поломка["що_змінено"].split(" · ")]
    поломка["що_змінено"] = " · ".join(сегм + хвіст)
    поломка["пара_виміряно"] = " · ".join(хвіст)      # той самий хвіст — у `пара_руки` звіту
    return поломка


def лише_правила(записи, коди):
    """Записи тіні лише цих кодів: пакет руки 1 стежить за всіма (`УСІ_КОДИ`), а звіт
    прогону каже про одне правило, яке випало."""
    наб = frozenset(коди or ())
    return [т for т in (записи or []) if _у(т.get("правило"), наб)]


# ── ПЕРЕМИКАЧ: КОНТЕКСТ ВИМКНЕНИХ ПРАВИЛ ───────────────────────────────────────
# ЧОМУ КОНТЕКСТ, А НЕ ПАРАМЕТР. Місця дії правила розкидані по пулу, суду й промпту
# на глибині 5–8 викликів; протягти параметр крізь кожен означало б змінити сигнатури
# десятків функцій рук 1, 3, 4. Контекст ставлять ДВА місця — пакет руки 2
# (`міст_пакет._пакет_каталогу`) і суд руки 2 (`міст_відповіді.від_моделі`), — а місця
# дії лише питають `вимкнене(код)`. Поза ними набір порожній.
_ВИМКНЕНО = _cv.ContextVar("правило_руки2_вимкнено", default=frozenset())
_СТЕЖИТИ = _cv.ContextVar("правило_руки2_стежити", default=frozenset())
_ТІНЬ = _cv.ContextVar("правило_руки2_тінь", default=None)


@_cl.contextmanager
def вимкнено(коди, стежити=()):
    """Усе всередині рахується без правил `коди`; правила `стежити` діють, але кожна їхня
    дія записується (рука 1 — щоб звіт знав, чи правило діяло і в неї). Тінь — заново."""
    т1 = _ВИМКНЕНО.set(frozenset(коди or ()))
    т2 = _СТЕЖИТИ.set(frozenset(стежити or ()))
    т3 = _ТІНЬ.set([])
    try:
        yield
    finally:
        _ТІНЬ.reset(т3)
        _СТЕЖИТИ.reset(т2)
        _ВИМКНЕНО.reset(т1)


def у_сесії(ф):
    """Декоратор ендпойнта: усередині — свіжий порожній контекст, на виході — скинутий.

    Так `увімкнути`/`стежити_за` (суд вирішує, яке правило, лише після жеребу, глибоко в
    тілі ендпойнта) не протікають ні в наступний виклик, ні в іншу руку. Джерело функції
    (`inspect.getsource`) лишається джерелом самого ендпойнта (`functools.wraps`)."""
    @_ft.wraps(ф)
    def обгортка(*a, **kw):
        with вимкнено(()):
            return ф(*a, **kw)
    return обгортка


def увімкнути(коди):
    """Вимкнути `коди` до кінця сесії `у_сесії` (суд руки 2 після жеребу)."""
    _ВИМКНЕНО.set(frozenset(коди or ()))
    _ТІНЬ.set([])


def стежити_за(коди):
    """Стежити за `коди` до кінця сесії `у_сесії` (суд руки 1 після жеребу): правило діє."""
    _СТЕЖИТИ.set(frozenset(коди or ()))
    _ТІНЬ.set([])


def вимкнені():
    """Набір кодів, вимкнених у цьому контексті (порожній поза рукою 2)."""
    return _ВИМКНЕНО.get()


def стежені():
    """Набір кодів, за якими стежать у цьому контексті (порожній поза рукою 1 прогону)."""
    return _СТЕЖИТИ.get()


def _у(код, наб):
    """Код у наборі. Суфіксний варіант (`K-CRA-01-N`) — разом із базою, коли в наборі база;
    варіант у наборі (`K-COL-06-M`) базу (`K-COL-06`) НЕ тягне."""
    if not наб or not код:
        return False
    к = str(код)
    return к in наб or (ІП.суфікс(к) is not None and ІП.база(к) in наб)


def вимкнене(код):
    """Чи код вимкнено (лише в контексті руки 2)."""
    return _у(код, _ВИМКНЕНО.get())


def торкнулось(код, де, **поля):
    """Місце дії питає перед тим, як діяти: записує дію в тінь, коли за правилом стежать
    або воно вимкнене, і повертає True лише коли вимкнене (тоді місце дії не діє)."""
    в, с = _у(код, _ВИМКНЕНО.get()), _у(код, _СТЕЖИТИ.get())
    if в or с:
        в_тінь(код, де, **поля)
    return в


def ключі_брифа_для(коди):
    """Ключі рядків брифа, які не їдуть у бриф руки 2: названі в переліку (ребра графа,
    рядки з чужим тегом, як `метал`) і всі рядки, чий код у `brief.ПРАВИЛО_РЯДКА` — вимкнений."""
    if not коди:
        return []
    import brief as _Б
    наб = set(коди)
    return sorted({к for з in ПЕРЕЛІК if наб & set(з["коди"]) for к in з["бриф"]}
                  | {к for к, (прав, _) in _Б.ПРАВИЛО_РЯДКА.items() if прав in наб})


def позначити(z):
    """Знахідку вимкненого правила — в тінь на місці народження: не блокує, не важить,
    не ремонтує й не просить каталог. Так вона нешкідлива навіть там, де її ніхто не
    відсіє (`відсіяти` прибирає її у точках збору). Повертає ту саму знахідку."""
    if isinstance(z, dict) and вимкнене(z.get("правило")):
        # ПОВТОРНО — ТЕЖ (Р2-2б): емітенти пишуть `dict(_зн(...), сила_нп=X)`, і копія несе вже
        # позначену тінь, але повернуту вагу; `обмежити_вагу` перед сумою ранжу кличе цю функцію
        # знову, і вага має знову стати нулем. Перша вага й блок лишаються в `тінь_руки_2`.
        if not z.get("тінь_руки_2"):
            z["тінь_руки_2"] = dict(блокувала=bool(z.get("блокує")), сила=z.get("сила"),
                                   сила_нп=z.get("сила_нп"))
        z["блокує"] = False
        z["сила_нп"], z["сила_нп_джерело"] = 0.0, "rule_off_hand_2"
        for к in ("ремонт", "запит_у_каталог", "ремонт_заяви"):
            z.pop(к, None)
    return z


def відсіяти(знахідки):
    """Знахідки без вимкнених правил; вимкнені — у тінь (рахуються, але не діють).
    Стежене правило лишається в переліку й лише записується в тінь."""
    вимк, стеж = _ВИМКНЕНО.get(), _СТЕЖИТИ.get()
    if not (вимк or стеж):
        return знахідки
    лишити = []
    for z in знахідки or []:
        п = z.get("правило") if isinstance(z, dict) else None
        if _у(п, вимк) or _у(п, стеж):
            т = z.get("тінь_руки_2") or {}
            в_тінь(п, "judge", сила=т.get("сила", z.get("сила")),
                   блокувала=т.get("блокувала", bool(z.get("блокує"))))
        if not _у(п, вимк):
            лишити.append(z)
    return лишити


def в_тінь(правило, де, **поля):
    """Записати в тінь дію правила (фільтр пулу, блокер структури, рядок промпту, знахідка),
    щоб `правило_діяло` бачило всі місця дії."""
    тінь = _ТІНЬ.get()
    if тінь is not None:
        тінь.append(dict(правило=правило, де=де, **поля))


def тінь():
    """Що вимкнене правило зробило б у цьому контексті (копія переліку)."""
    return list(_ТІНЬ.get() or [])


def зведення_тіні(записи=None):
    """Тінь зведенням: {«правило·де»: скільки} — без повторів одного свідка (його питають
    десятки разів на прогін). Порожньо — правило не діяло б ніде."""
    з = {}
    for т in (тінь() if записи is None else записи):
        к = "%s·%s" % (т.get("правило"), т.get("де"))
        з[к] = з.get(к, 0) + 1
    return з
