    т2 = _СТЕЖИТИ.set(frozenset(стежити or ()))
    т3 = _ТІНЬ.set([])
    try:
        yield
    finally:
        _ТІНЬ.reset(т3)
        _СТЕЖИТИ.reset(т2)
        _ВИМКНЕНО.reset(т1)
        _ЗЛАМАНО.reset(т0)


