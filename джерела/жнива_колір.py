def слово_з_lab(lab):
    """Слово ЛЕКСИКОНУ для виміряного Lab: вікно, що ВМІЩАЄ вимір, найтісніше з таких.

    Повертає (слово, у_вікні). Коли вимір не вміщається в жодне вікно, береться
    найближче за нормованою відстанню, і `у_вікні` False — запис це показує.
    """
    L, C_, h = CS.lch(lab)
    вміщають, поруч = [], []
    for сл, (Lmin, Lmax, Cmin, Cmax, дуга) in V.ЛЕКСИКОН.items():
        if сл in V.ВІКНА_КРАМНИЦЬ:
            continue            # слово поля кольору крамниці, не слово виміру
        тісно = (Lmax - Lmin) * (Cmax - Cmin)
        у_L = Lmin <= L <= Lmax
        у_C = Cmin <= C_ <= Cmax
        у_h = True if (not дуга or C_ < 10) else V.у_дузі(h, дуга)
        if у_L and у_C and у_h:
            вміщають.append((тісно, сл))
            continue
        d = (max(0, Lmin - L) + max(0, L - Lmax)) / 10.0 + (max(0, Cmin - C_) + max(0, C_ - Cmax)) / 10.0
        if дуга and C_ >= 10 and not V.у_дузі(h, дуга):
            a, b = дуга
            d += min(min(abs(h - a), 360 - abs(h - a)), min(abs(h - b), 360 - abs(h - b))) / 30.0
        поруч.append((d, тісно, сл))
    if вміщають:
        return min(вміщають)[1], True
    return min(поруч)[2], False


def поправка_тла(bgr, маска, стеля=1.25):
    """Експозиція за білим тлом: (bgr, підсилення) — або (bgr, None), коли тло не біле.

    ЧОМУ (виміряно на вибірці 60). Крамничне фото на білому
    безшовному тлі знято з недодержкою: молочні штани мали L* 71 і лягли у вікно
    «срібний», хоча тло поруч — L* 88, а не 100. Вікна ЛЕКСИКОНУ писані для
    кольору речі, а не для кадру з недодержкою. Тло, яке фотограф мав за біле
    (світле й безбарвне), — це еталон білого в самому кадрі: канали множаться
    так, щоб воно стало білим. Стеля підсилення 1.25 — щоб світло-сіре тло не
    перетворило сіру річ на білу; кольорове чи темне тло поправки не дає.
    """
    import numpy as np
    h, w = bgr.shape[:2]
    к = max(4, min(h, w) // 40)
    рамка = np.zeros((h, w), bool)
    рамка[:к] = рамка[-к:] = True
    рамка[:, :к] = рамка[:, -к:] = True
    рамка &= маска <= 127
    if рамка.sum() < 100:
        return bgr, None
    тло = np.median(bgr[рамка], axis=0).astype("float32")
    L, C_, _ = CS.lch(CS.to_lab(tuple(int(x) for x in тло[::-1])))
    if L < 80 or C_ >= 8:
        return bgr, None
    підсил = np.clip(250.0 / np.maximum(тло, 1.0), 1.0, стеля)
    return np.clip(bgr.astype("float32") * підсил, 0, 255).astype("uint8"), round(float(підсил.mean()), 3)


def виміряти_колір(шлях, маска, к=4, сід=17):
    """k-means у Lab по пікселях маски → (кластери {частка, lab, hex, слово}, поправка тла).

    Кластери з ОДНАКОВИМ словом зливаються: розділяти «чорний» на дві тіні не
    має сенсу для правил, які читають слово, а частку роздрібнення применшує.
    """
    import cv2, numpy as np
    bgr, поправка = поправка_тла(cv2.imread(шлях), маска)
    lab = cv2.cvtColor(bgr, cv2.COLOR_BGR2LAB).astype("float32")
    lab[:, :, 0] *= 100.0 / 255.0
    lab[:, :, 1] -= 128.0
    lab[:, :, 2] -= 128.0
    пікс = lab[маска > 127]
    if len(пікс) < 300:
        return [], поправка
    if len(пікс) > 20000:
        пікс = пікс[np.random.RandomState(сід).choice(len(пікс), 20000, replace=False)]
    к = min(к, max(1, len(пікс) // 100))
    крит = (cv2.TERM_CRITERIA_EPS + cv2.TERM_CRITERIA_MAX_ITER, 25, 1.0)
    _, мітки, центри = cv2.kmeans(пікс.astype("float32"), к, None, крит, 5, cv2.KMEANS_PP_CENTERS)
    мітки = мітки.ravel()
    за_словом = {}
    for i, ц in enumerate(центри):
        частка = float((мітки == i).mean())
        if частка < 0.02:
            continue
        сл, у_вікні = слово_з_lab(tuple(float(x) for x in ц))
        куди = за_словом.setdefault(сл, dict(слово=сл, частка=0.0, lab=[0.0, 0.0, 0.0], у_вікні=у_вікні))
        сума = куди["частка"] + частка
        куди["lab"] = [(куди["lab"][j] * куди["частка"] + float(ц[j]) * частка) / сума for j in range(3)]
        куди["частка"] = сума
        куди["у_вікні"] = куди["у_вікні"] or у_вікні
    вих = []
    for к_ in за_словом.values():
        к_["lab"] = [round(x, 2) for x in к_["lab"]]
        к_["частка"] = round(к_["частка"], 3)
        к_["hex"] = CS.hex_з_lab(tuple(к_["lab"]))
        вих.append(к_)
    return sorted(вих, key=lambda x: -x["частка"]), поправка


# ── ЗВЕДЕННЯ КОЛЬОРУ І ВПЕВНЕНІСТЬ ──────────────────────────────────────────
def звести_колір(кластери, слово_моделі, слова_крамниці_):
    """Вимір + слово моделі → основний і другий колір, і `спір`, коли не збігаються.

    Кластер обирається НЕ найбільший, а найбільший У СІМ'Ї ТОНУ, яку назвала
    модель: на фото сукні в руках моделі найбільшим кластером буває тінь або
    підкладка. Коли в сім'ї моделі кластера нема — береться найбільший, і запис
    несе `спір` з обома словами, щоб фід міг лишити слово крамниці.
    """
    if not кластери:
        return None, None, None
    сім_я_моделі = сім_я_слова(слово_моделі) if слово_моделі else None
    у_сім_ї = [к for к in кластери if сім_я_слова(к["слово"]) == сім_я_моделі] if сім_я_моделі else []
    перший = основний = (у_сім_ї or кластери)[0]
    тон_невідомо = основний.get("тон", 0) is None        # сегмент поверхні 2.12 з тоном нижче невизначеності
    if тон_невідомо:
        основний = за_вікном_слова(основний, слова_крамниці_)
        if основний is None:
            return None, None, None
    спір = None
    if слово_моделі and not у_сім_ї and not (тон_невідомо and сім_я_слова(основний["слово"]) == сім_я_моделі):
        спір = dict(вимір=основний["слово"], модель=слово_моделі,
                    сім_я_виміру=сім_я_слова(основний["слово"]), сім_я_моделі=сім_я_моделі,
                    крамниця=(слова_крамниці_ or [None])[0],
                    чому="сім'я тону виміру не збіглася зі словом моделі")
    другий = None
    for к in кластери:
        if к is перший:
            continue
        # другу поверхню судить вимір (`перший`), не точка вікна слова, що могла замінити основний
        if к["частка"] < 0.2 or сім_я_слова(к["слово"]) == сім_я_слова(перший["слово"]):
            continue
        if _тінь(перший["lab"], к["lab"]):
            continue
        другий = к
        break
    return основний, другий, спір


def за_вікном_слова(сегмент, слова_крамниці_):
    """Сегмент із невідомим тоном → колір споживача (ПРОДУКТ п.18; рішення менеджера 25.10).

    Вимір у вікні першого слова крамниці, що має вікно (світлота й хрома в межах; тон не судиться —
    його не виміряно), — лишається виміром під словом крамниці (слово виміру — здогад тону). Інакше точка вікна, найближча до виміру: світлота —
    вимір освітленої частини, хрома — вимір у межах вікна, а нижче нижньої межі слова — точка вікна,
    сумісна з виміром у межах невизначеності (до C + U), найближча до середини вікна (світло кадру
    з'їдає хрому, тож вимір — лише «щонайменше»), тон — середина дуги слова (слово без дуги — нейтраль). Нема слова з вікном — None: колір з фото
    невідомо (світлота лишається в `поверхня`; тип «невідомо зі світлотою» — крок 2.13)."""
    import math
    def вікно(с):
        ім, в, _ = V.вікно_зі_слова(с)
        с_ = (с or "").strip().lower()
        return (ім, в) if ім else ((с_, V.ЛЕКСИКОН[с_]) if с_ in V.ЛЕКСИКОН else (None, None))
    ім, в = next(((і, в_) for с in слова_крамниці_ or [] for і, в_ in [вікно(с)] if і), (None, None))
    if ім is None:
        return None
    L, (C, _) = сегмент["світлота"], сегмент["хрома"]
    if в[0] <= сегмент["lab"][0] <= в[1] and в[2] <= C <= в[3]:
        return dict(сегмент, слово=ім, за_чим="вимір у вікні слова «%s»; тон невідомо" % ім)
    д = в[4]
    h = 0.0 if д is None else ((д[0] + ((д[1] - д[0]) if д[0] <= д[1] else (д[1] + 360 - д[0])) / 2) % 360)
    if д is None:
        C = 0.0
    elif C < в[2]:                      # хрома нижче слова: «щонайменше» — до середини вікна в межах C ± U
        низ, верх = в[2], min(в[3], C + сегмент["хрома"][1])
        C = min(max((в[2] + в[3]) / 2.0, низ), верх) if низ <= верх else в[2]
    else:
        C = min(C, в[3])
    lab = (min(max(L, в[0]), в[1]), C * math.cos(math.radians(h)), C * math.sin(math.radians(h)))
    return dict(сегмент, слово=ім, lab=[round(x, 2) for x in lab], hex=CS.hex_з_lab(lab), у_вікні=True,
                за_чим="вікно слова «%s»: тон невідомо, світлота — вимір" % ім)


def _тінь(a, b, поріг=8.0, розрив_L=30.0):
    """Чи другий кластер — лише тінь першого, а не другий колір речі.

    Прийом із чужого колірного гейта (`system/gates/color.py`): перед порівнянням
    світлота одного зсувається до іншого — що лишилось, те й є різниця тону і
    хроми. На пробі біла в'язка дала «білий 0.64 + срібний 0.34», і срібний був
    складкою в тіні, а не другим кольором.
    РОЗРИВ СВІТЛОТИ — ВИНЯТОК: біле з чорною вставкою теж має однаковий тон
    (обидва ахроматичні), але це два кольори, а не тінь; при |ΔL| ≥ 30 рішення
    лишається за часткою площі.
    """
    if abs(a[0] - b[0]) >= розрив_L:
        return False
    return CS.de00((b[0], a[1], a[2]), tuple(b)) < поріг


def впевненість(маска_частка, основний, спір, слова_крамниці_, друге_фото_de):
    """Впевненість — ЗІ ЗГОДИ СВІДКІВ, а не з самооцінки моделі.

    V1 питала модель «наскільки ти впевнена» і діставала 0.9 на логотипі. Тут
    четверо свідків, і кожен або згоден, або мовчить: маска (чи є що міряти),
    слово моделі, слово крамниці, друге фото (той самий колір з іншого кадру).
    Свідок, який мовчить, ваги не має — частка рахується від присутніх.
    """
    ваги, бали = [], []
    ваги.append(0.35)
    бали.append(min(1.0, (маска_частка or 0) / 0.25))
    if спір is not None or основний is not None:
        ваги.append(0.25)
        бали.append(0.0 if спір else 1.0)
    if слова_крамниці_:
        ваги.append(0.20)
        сім = {сім_я_слова(с) for с in слова_крамниці_}
        бали.append(1.0 if основний and сім_я_слова(основний["слово"]) in сім else 0.0)
    if друге_фото_de is not None:
        ваги.append(0.20)
        бали.append(1.0 if друге_фото_de <= 5 else (0.5 if друге_фото_de <= 10 else 0.0))
    if основний and not основний.get("у_вікні", True):
        бали = [б * 0.8 for б in бали]
    return round(sum(в * б for в, б in zip(ваги, бали)) / sum(ваги), 2)


def світліша_половина(шлях, маска):
    """Lab, хрома і слово по СВІТЛІШІЙ половині пікселів маски — ОКРЕМИЙ вимір,
    рішення він не міняє (вікна `verify.ЛЕКСИКОН` не чіпаємо).

    ЧОМУ. Тінь на тканині з'їдає хрому: темно-синя річ у півтіні дає
    C* < 8 і лягає у вікно «графіт» чи «чорний», хоча на світлі вона синя. Світліша
    половина пікселів маски — та сама річ при світлі; її хрома каже, чи це справді
    ахроматика, чи темний тон. Число стоїть у записі, щоб проба показала різницю.
    """
    import cv2, numpy as np
    bgr, _ = поправка_тла(cv2.imread(шлях), маска)
    lab = cv2.cvtColor(bgr, cv2.COLOR_BGR2LAB).astype("float32")
    lab[:, :, 0] *= 100.0 / 255.0
    lab[:, :, 1] -= 128.0
    lab[:, :, 2] -= 128.0
    пікс = lab[маска > 127]
    if len(пікс) < 300:
        return None
    ц = tuple(float(x) for x in пікс[пікс[:, 0] >= np.median(пікс[:, 0])].mean(axis=0))
    L, C_, h = CS.lch(ц)
    сл, у_вікні = слово_з_lab(ц)
    return dict(lab=[round(x, 2) for x in ц], C=round(C_, 1), тон=round(h, 1),
                слово=сл, у_вікні=у_вікні)


