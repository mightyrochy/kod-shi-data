def слово_з_lab(lab):
    """Підпис сегмента за спільним словником виміру поверхні."""
    from surface import слово_з_lab as слово
    return слово(lab)


def поправка_тла(bgr, маска, стеля=1.25):
    """Сумісний формат кадру для спільної поправки білого тла."""
    import numpy as np
    from surface import поправка_тла as виправити
    h, w = bgr.shape[:2]
    rgb = bgr[:, :, ::-1].reshape(-1, 3).tolist()
    м = (маска > 127).tobytes()
    rgb, підсил = виправити(rgb, м, w, h, стеля)
    return np.asarray([tuple(reversed(p)) for p in rgb], dtype="uint8").reshape(h, w, 3), підсил


def виміряти_колір(шлях, маска, к=4, сід=17):
    """Сумісний вхід жнив: сегменти спільної поверхні та поправка експозиції.

    Параметр к задавав кількість кластерів старого виміру. Кількість поверхонь
    тепер визначає ядро; старий виклик з іншим к не маскуємо.
    """
    import cv2
    if к != 4:
        raise ValueError("Кількість кластерів визначає вимір поверхні")
    п = виміряти_поверхню(читати_bgr(шлях), маска, сід=сід)
    return (п["сегменти"] if п["придатна"] else []), п["поправка"]


