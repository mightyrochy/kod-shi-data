ПРОВАЛ = 0.25              # середина між центрами заселена слабше за чверть країв — дві речовини
# НЕВИЗНАЧЕНІСТЬ ХРОМИ (рішення менеджера 25.10, рядок 9356). Хрома й тон сегмента — вимір, лише коли
# вони більші за невизначеність: розкид освітленої частини сегмента плюс невідоме світло кадру. Світло
# кадру не вгадується порогом, а береться виміряним розподілом: на 3 234 дизайнах каталогу зі словом
# без хроми («чорний», «сірий», «білий», «графіт») увесь виміряний C* і є зсув світла кадру
# (`verify.ДРІЖ_AB`, блок над ним); 90-й перцентиль за смугами L* — нижче. Світле тло поза маскою на
# 41 кадрі стенда 2.12 дало менше (медіана 1.0, p90 2.8, найбільше 10.2): крамниці вирівнюють біле тло
# окремо від речі, тож тло — нижня оцінка, а розподіл речей каталогу — та, що береться.
# (верхня межа L* смуги, p90 C* слів без хроми)
ДРІЖ_СВІТЛА = ((15, 3.9), (30, 7.2), (45, 6.9), (60, 8.6), (75, 11.5), (90, 7.8), (101, 4.5))
ЗАПАСНА_НЕВІДОМО = "запасна маска — колір з фото невідомо (рішення 24.10: невпевнена маска)"


def невизначеність_хроми(L, розкид_ab):
    """Невизначеність C* точки (одиниці a*b*): світло кадру за смугою L* ⊕ розкид освітленої частини."""
    import math
    дріж = next(д for межа, д in ДРІЖ_СВІТЛА if L < межа)
    return math.hypot(дріж, розкид_ab)


def _лаб(bgr):
    import cv2
    lab = cv2.cvtColor(bgr, cv2.COLOR_BGR2LAB).astype("float32")
    lab[:, :, 0] *= 100.0 / 255.0
    lab[:, :, 1] -= 128.0
    lab[:, :, 2] -= 128.0
    return lab


def _точка_поверхні(p):
    """Точка й розкид поверхні: колір її освітленої частини без відблиску.

    Тінь робить колір темнішим І сірішим (рядок 6431: шоколадна замша →
    #1e1915, C* 3.8): у лінійному світлі пікселі множаться на число, і хрома
    гасне разом зі світлотою. Тому точка — середнє пікселів між медіаною
    світлоти і її 90-м перцентилем: освітлена грань речі, яку бачить око, без
    найтемніших складок і без найсвітліших бліків.
    Безбарвній поверхні (хрома освітленої грані < БЕЗБАРВНА_C) нема чого
    відновлювати: тінь міняє лише світлоту, і око судить її за серединою —
    точка тоді середнє між 25-м і 75-м перцентилем (чорний не стає графітом)."""
    import numpy as np
    L = p[:, 0]

    def смуга(lo, hi):
        с = p[(L >= np.percentile(L, lo)) & (L <= np.percentile(L, hi))]
        return (с if len(с) >= 20 else p).mean(axis=0)
    точка = смуга(50, 90)
    if float(np.hypot(точка[1], точка[2])) < БЕЗБАРВНА_C:
        точка = смуга(25, 75)
    розкид = float(np.percentile(np.linalg.norm(p - точка, axis=1), 75))
    розкид_ab = float(np.percentile(np.linalg.norm(p[:, 1:] - точка[1:], axis=1), 75))
    світла = p[(L >= np.percentile(L, 50)) & (L <= np.percentile(L, 90))]
    світла = світла if len(світла) >= 20 else p
    розкид_світла = float(np.median(np.linalg.norm(світла[:, 1:] - np.asarray(точка[1:]), axis=1)))
    return tuple(float(x) for x in точка), розкид, розкид_ab, (розкид_світла, float(світла[:, 0].mean()))


def _промінь(а, б):
    """Чи темніша з двох точок Lab — тінь світлішої: та сама фарба, менше світла (рішення 25.10, п.5).

    Тінь множить світло на число в лінійному просторі (XYZ — лінійний перетвір RGB): точки однієї
    фарби лежать на промені до чорного. Світлішу точку зсуваємо по цьому променю до світлоти темнішої
    й міряємо, що лишилось (ΔE00 < `ПРОМІНЬ_ДЕ`). Змішування двох фарб (розмиті смуги, дрібний принт)
    лежить на відрізку МІЖ ними, не на промені, тож двох кольорів воно в одну поверхню не зливає,
    хоч би й заповнило середину без провалу."""
    св, тм = (а, б) if а[0] >= б[0] else (б, а)
    X, Y, Z = CS.to_xyz(св)
    Yт = CS.to_xyz(тм)[1]
    if Y <= 0:
        return False
    к = Yт / Y
    return CS.de00(CS.from_xyz(к * X, к * Y, к * Z), tuple(тм)) < ПРОМІНЬ_ДЕ


def _на_відрізку(м, а, б):
    """Чи точка м лежить на відрізку між а і б (змішування двох фарб): t у (0.15, 0.85) і ΔE00 до
    точки відрізка < `РІЗНИЦЯ_ОКА`. Змішування міряється в лінійному XYZ — так змішує світло пікселя."""
    import numpy as np
    xa, xb, xm = (np.asarray(CS.to_xyz(т)) for т in (а, б, м))
    в = xb - xa
    дв = float(в @ в)
    if дв <= 0:
        return False
    t = float((xm - xa) @ в / дв)
    return 0.15 < t < 0.85 and CS.de00(CS.from_xyz(*(xa + t * в)), tuple(м)) < РІЗНИЦЯ_ОКА


def _одне_світло(а, б):
    """Чи дві точки Lab — та сама фарба під різним світлом (складка, тінь під рукою).

    `_тінь` порівнює хрому за однієї світлоти й при |ΔL| ≥ 30 відмовляє, а
    глибока тінь бежевого жакета на пробі темніша на 30 і НАСИЧЕНІША: у складці
    тканина світить сама на себе (міжвідбиття), тож тон лишається, а хрома
    росте. Тут: обидві точки кольорові, тон той самий (Δh < ТОН_ТІНІ), темніша
    не насиченіша за світлішу більш ніж удвічі (червоне з рожевим — два кольори,
    не тінь). Ахроматичні пари судить провал, а біле з чорним — `РОЗРИВ_СВІТЛОТИ`."""
    import math
    (L1, C1, h1), (L2, C2, h2) = CS.lch(а), CS.lch(б)
    if min(C1, C2) < БЕЗБАРВНА_C or abs(L1 - L2) >= РОЗРИВ_СВІТЛОТИ:
        return False
    if min(abs(h1 - h2), 360 - abs(h1 - h2)) >= ТОН_ТІНІ:
        return False
    (Cсв, Cтем) = (C1, C2) if L1 >= L2 else (C2, C1)
    return Cтем <= 2 * Cсв + 5


def виміряти_поверхню(bgr, маска, арр=None, сід=17, джерело=None):
    """Поверхня речі за маскою → dict(сегменти, позначки, візерунок, придатна, чому, поправка).

    ЧОМУ (наряд 2.12; рядки 6431–6433, 5026, 5669, 5666). Одна точка k-means
    не мала області застосовності: тінь, відблиск, шкіра під прозорою тканиною й
    частини принта ставали «кольором». Тут:
    1. край маски (2 px) і пересвічені пікселі — не колір речі (`край`, `кліп`);
    2. шкіра — за картою ATR усередині маски (`шкіра`); кластер, близький до
       шкіри з того самого кадру, коли поруч є інша тканина, — `прозоре`;
    3. одна поверхня — кластери, які око не розрізняє, і тінь тієї самої фарби
       (`_тінь`, `_одне_світло`, промінь до чорного `_промінь`); решта — інша
       речовина: другий колір, принт чи деталь. Кластер на відрізку між двома
       більшими поверхнями — їхнє змішування (`_на_відрізку`): площа його
       йде ближчій, а в точку й у слова він не йде (рішення менеджера 25.10);
    4. світліша й сіріша за головну поверхня до чверті маски — `відблиск`;
    5. точка поверхні — `_точка_поверхні` (освітлена частина без бліку);
    6. лишилось менше половини маски або головна поверхня розкидана
       (`РОЗКИД_ПОВЕРХНІ`) — «невідомо»: колір з фото не міряють;
    7. тон і хрома сегмента — вимір, лише коли C* більша за невизначеність
       (`невизначеність_хроми`: світло кадру ⊕ розкид); інакше `тон` None —
       «тон невідомо», і колір дає вікно слова крамниці (`звести_колір`).
    `джерело` маски «запасна» — колір з фото невідомо на будь-якому кадрі (рядок 9351).
    `арр` — карта міток ATR будь-якого розміру або None (кадр без людини).
    Сегменти: частка — від придатної площі, `плям` — окремих плям сегмента.
    """
    import cv2, numpy as np
    h, w = bgr.shape[:2]
    м = (маска if маска.shape[:2] == (h, w) else
         cv2.resize(маска, (w, h), interpolation=cv2.INTER_NEAREST)) > 127
    к_ = min(1.0, ДОВГА_СТОРОНА / float(max(h, w)))
    if к_ < 1.0:
        розм = (max(1, int(round(w * к_))), max(1, int(round(h * к_))))
        bgr = cv2.resize(bgr, розм, interpolation=cv2.INTER_AREA)
        м = cv2.resize(м.astype("uint8"), розм, interpolation=cv2.INTER_NEAREST) > 0
        h, w = bgr.shape[:2]
    bgr, поправка = поправка_тла(bgr, м.astype("uint8") * 255)
    вих = dict(сегменти=[], позначки={}, візерунок=None, придатна=False, чому="", поправка=поправка)
    if джерело == "запасна":
        вих["чому"] = ЗАПАСНА_НЕВІДОМО
        return вих
    всього = int(м.sum())
    if всього < 300:
        вих["чому"] = "маска менша за 300 px"
        return вих
    lab = _лаб(bgr)
    шк_в, шк_поза = np.zeros((h, w), bool), np.zeros((h, w), bool)
    if арр is not None:
        а = cv2.resize(np.asarray(арр, "uint8"), (w, h), interpolation=cv2.INTER_NEAREST)
        шк = np.isin(а, ШКІРА_БЕЗ_ВОЛОССЯ)
        шк_в = шк & м
        шк_поза = (cv2.erode(шк.astype("uint8"), np.ones((5, 5), "uint8")) > 0) & ~м
    ядро = cv2.erode(м.astype("uint8"), np.ones((5, 5), "uint8")) > 0
    if ядро.sum() < 0.5 * всього:            # тонка річ (ремінець, ланцюжок): край не знімаємо
        ядро = м.copy()
    кліп = м & (bgr.min(axis=2) >= 250)      # пересвіт — білий у всіх каналах, не насичений червоний
    робоча = ядро & ~шк_в & ~кліп
    позн = dict(край=round(float((м & ~ядро).sum()) / всього, 3), шкіра=round(float(шк_в.sum()) / всього, 3),
                кліп=round(float((кліп & ядро).sum()) / всього, 3), прозоре=0.0, відблиск=0.0)
    вих["позначки"] = позн
    пікс = lab[робоча]
    if len(пікс) < 300:
        вих["чому"] = "після позначок лишилось < 300 px"
        return вих
    вибір = пікс
    if len(вибір) > 20000:
        вибір = вибір[np.random.RandomState(сід).choice(len(вибір), 20000, replace=False)]
    к = min(К_ПОВЕРХНІ, max(1, len(вибір) // 100))
    крит = (cv2.TERM_CRITERIA_EPS + cv2.TERM_CRITERIA_MAX_ITER, 25, 1.0)
    cv2.setRNGSeed(сід)
    _, _, центри = cv2.kmeans(вибір.astype("float32"), к, None, крит, 3, cv2.KMEANS_PP_CENTERS)
    мітки_п = ((пікс[:, None, :] - центри[None, :, :]) ** 2).sum(-1).argmin(1)
    ц = [tuple(float(x) for x in центри[i]) for i in range(к)]
    n = np.bincount(мітки_п, minlength=к).astype(float)

    # 1. шкіра крізь тканину: лише коли поруч є інша, не схожа на шкіру тканина
    викл = set()
    if шк_поза.sum() >= 200:
        шкіра_lab = tuple(float(x) for x in np.median(lab[шк_поза], axis=0))
        схожі = [i for i in range(к) if CS.de00(ц[i], шкіра_lab) <= ШКІРА_ДЕ]
        if схожі and n.sum() - n[схожі].sum() >= 0.25 * n.sum():
            викл.update(схожі)
            позн["прозоре"] = round(float(n[схожі].sum()) / всього, 3)
    # 2. поверхні: злиття від найближчих груп. Неразрізненні (ΔE00 < РІЗНИЦЯ_ОКА) чи
    #    та сама фарба під іншим світлом (`_одне_світло`, `_промінь`: тінь — промінь до
    #    чорного в лінійному RGB) без провалу між ними — одна поверхня. Зсув у Lab
    #    (`_тінь`) і сама «нема провалу» більше не зливають (рядок 9357): перший зливав
    #    різні речовини, друга — розмиті смуги й дрібний принт, і другий колір губився.
    групи = [[i] for i in range(к) if i not in викл and n[i]]

    def центр(г):
        return tuple(float(x) for x in пікс[np.isin(мітки_п, г)].mean(axis=0))

    def провал(а, б):
        """Чи між групами а, б у пікселях провал — межа двох речовин, а не тінь.

        Пікселі обох груп проєктуються на відрізок між центрами. Тінь дає неперервний
        перехід світла — середина заселена; межа двох речовин — смуга розмиття в 1–2 px,
        середина майже порожня. Сам провал поверхні не зливає (розмиті смуги заповнюють
        середину, рядок 9357) — він лише не дає променю злити дві речовини однієї барви
        (молочна шкіра й бежева замша №8, чорне поні й марсала №39)."""
        pa, pb = пікс[np.isin(мітки_п, а)], пікс[np.isin(мітки_п, б)]
        ca, cb = pa.mean(axis=0), pb.mean(axis=0)
        в = cb - ca
        дв = float(в @ в)
        if дв < 1.0:
            return False
        t = (np.vstack([pa, pb]) - ca) @ в / дв
        гіст = np.histogram(t, bins=10, range=(0.0, 1.0))[0].astype(float)
        краї = min(гіст[:2].max(), гіст[-2:].max())
        return краї > 0 and гіст[3:7].min() / краї < ПРОВАЛ
    while len(групи) > 1:
        цг = [центр(г) for г in групи]
        пари = sorted((CS.de00(цг[x], цг[y]), x, y)
                      for x in range(len(групи)) for y in range(x + 1, len(групи)))
        for de, x, y in пари:
            if abs(цг[x][0] - цг[y][0]) >= РОЗРИВ_СВІТЛОТИ:
                continue        # сірі тіні між білим і чорним заповнюють провал, але речовин дві
            if de < РІЗНИЦЯ_ОКА or ((_одне_світло(цг[x], цг[y]) or _промінь(цг[x], цг[y]))
                                    and not провал(групи[x], групи[y])):
                групи[x] = групи[x] + групи.pop(y)
                break
        else:
            break
    # змішування: група на відрізку між двома більшими — не третій колір (від найменших)
    nг = lambda г: float(n[г].sum())
    дод = {}
    while len(групи) > 2:
        цг = [центр(г) for г in групи]
        суміш = next(((з, x, y) for з in sorted(range(len(групи)), key=lambda і: nг(групи[і]))
                      for x in range(len(групи)) for y in range(x + 1, len(групи))
                      if з not in (x, y) and min(nг(групи[x]), nг(групи[y])) > nг(групи[з])
                      and _на_відрізку(цг[з], цг[x], цг[y])), None)
        if суміш is None:
            break
        з, x, y = суміш
        ближча = x if CS.de00(цг[з], цг[x]) <= CS.de00(цг[з], цг[y]) else y
        ключ = tuple(групи[ближча])
        дод[ключ] = дод.get(ключ, 0.0) + nг(групи[з])
        групи.pop(з)
    позн["змішування"] = round(sum(дод.values()) / всього, 3)
    карта = np.full((h, w), -1, "int32")
    карта[робоча] = мітки_п
    пов = []
    for г in групи:
        маск_г = np.isin(мітки_п, г)
        точка, розкид, розкид_ab, розкид_світла = _точка_поверхні(пікс[маск_г])
        пов.append(dict(кл=г, n=float(маск_г.sum()) + дод.get(tuple(г), 0.0), lab=точка, розкид=розкид,
                        розкид_ab=розкид_ab, розкид_світла=розкид_світла[0], світлота=розкид_світла[1]))
    пов.sort(key=lambda x: -x["n"])
    головна = пов[0]
    Lг, Cг, _ = CS.lch(головна["lab"])
    # 3. відблиск: світліша й безбарвніша за головну поверхня (метал, сатин, лак)
    лишились, відбл = [головна], 0.0
    for п in пов[1:]:
        Lп, Cп, _ = CS.lch(п["lab"])
        if Lп - Lг >= 15 and Cп <= max(6.0, 0.5 * Cг) and п["n"] <= ЧАСТКА_ВІДБЛИСКУ * всього:
            відбл += п["n"]
        else:
            лишились.append(п)
    позн["відблиск"] = round(відбл / всього, 3)
    корисно = sum(п["n"] for п in лишились)
    вих["придатна"] = корисно / всього >= ПРИДАТНА_ЧАСТКА
    межа_ab = max(РОЗКИД_ТОНУ, 0.5 * CS.lch(головна["lab"])[1])
    if вих["придатна"] and (головна["розкид"] > РОЗКИД_ПОВЕРХНІ or головна["розкид_ab"] > межа_ab):
        # провал не знайдено, а пікселі розкидані від білого до чорного (тонкі
        # ремінці, намистини) чи між різними тонами (чорний ремінь з коричневою
        # підкладкою, міст — пряжка): одного кольору тут нема
        вих["придатна"] = False
        вих["чому"] = "головна поверхня неоднорідна: розкид ΔE %.0f (межа %.0f), за тоном %.0f (межа %.0f)" % (
            головна["розкид"], РОЗКИД_ПОВЕРХНІ, головна["розкид_ab"], межа_ab)
        return вих
    if not вих["придатна"]:
        вих["чому"] = "колір речі — %.0f%% маски; решта — %s" % (100 * корисно / всього, ", ".join(
            "%s %.0f%%" % (к_, 100 * в) for к_, в in позн.items() if в >= 0.05))
        return вих
    # 4. сегменти і візерунок: плями кожної поверхні після згладжування міток
    сег = []
    for п in лишились:
        частка = п["n"] / корисно
        if частка < МІН_ЧАСТКА_СЕГМЕНТА:
            continue
        пл = np.isin(карта, п["кл"]).astype("uint8")
        пл = cv2.morphologyEx(пл, cv2.MORPH_OPEN, np.ones((3, 3), "uint8"))
        кn, _, ст, _ = cv2.connectedComponentsWithStats(пл, connectivity=8)
        плям = int((ст[1:, cv2.CC_STAT_AREA] >= max(4, 0.002 * всього)).sum())
        сл, у_вікні = слово_з_lab(п["lab"])
        Lп, Cп, hп = CS.lch(п["lab"])
        нв = невизначеність_хроми(п["світлота"], п["розкид_ab"])
        сег.append(dict(слово=сл, частка=round(частка, 3), lab=[round(x, 2) for x in п["lab"]],
                        hex=CS.hex_з_lab(п["lab"]), у_вікні=у_вікні, розкид=round(п["розкид"], 1), плям=плям,
                        світлота=round(п["світлота"], 1), хрома=[round(Cп, 1), round(нв, 1)],
                        тон=round(hп) if Cп > нв else None))
    вих["сегменти"] = сег
    малюнок = [с for с in сег[1:] if с["частка"] >= ЧАСТКА_ПЛЯМ]
    if any(с["плям"] >= ПЛЯМ_ПРИНТА for с in малюнок):
        вих["візерунок"] = "принт"
    elif any(с["частка"] >= ЧАСТКА_ДРУГОГО for с in малюнок):
        вих["візерунок"] = "двоколірний"
    else:
        вих["візерунок"] = "однотонний"
    вих["чому"] = "%s; придатна %.0f%% маски" % (вих["візерунок"], 100 * корисно / всього)
    if сег and сег[0]["тон"] is None:
        вих["чому"] += "; тон невідомо: C* %.1f ≤ невизначеність %.1f (світло кадру за L* %.0f ⊕ розкид)" % (
            сег[0]["хрома"][0], сег[0]["хрома"][1], сег[0]["світлота"])
    return вих


def стиснути_поверхню(п):
    """Поверхня → короткий запис (2.12): {візерунок, придатна, позначки, сегменти, чому}.

    Сегмент — [слово, частка, hex, розкид]: з цього читач бачить, чи колір
    однорідний, а не лише яке він слово."""
    if not п:
        return None
    return dict(візерунок=п["візерунок"], придатна=п["придатна"], чому=п["чому"],
                позначки={к: в for к, в in п["позначки"].items() if в},
                сегменти=[[с["слово"], с["частка"], с["hex"], с["розкид"]] for с in п["сегменти"]])


def поверхня_фото(шлях, слот):
    """Фото → dict(частка, кластери, чому, джерело, світліша, поверхня) — вимір поверхні (2.12).

    `кластери` — сегменти `виміряти_поверхню`, коли поверхня придатна; інакше []
    і колір із фото не міряють — він іде за правилами кольору крамниці, а `чому`
    каже чому. Ключі сегмента ті самі, що в кластерах `виміряти_колір` (слово,
    частка, lab, hex, у_вікні), тож `звести_колір` і читачі їх беруть як є."""
    import cv2
    from жнива_маски import _мітки_atr
    м, dom, чому, джерело = маска_речі(шлях, слот)
    if м is None:
        return dict(частка=0.0, кластери=[], чому=чому, джерело=джерело, світліша=None, поверхня=None)
    try:
        арр = _мітки_atr(шлях)
    except Exception:               # без ATR шкіру не позначимо, а колір виміряємо
        арр = None
    п = виміряти_поверхню(cv2.imread(шлях), м, арр, джерело=джерело)
    if п["поправка"]:
        чому += "; тло біле, експозиція ×%.2f" % п["поправка"]
    чому += "; поверхня: " + п["чому"]
    частка_кадру = float((м > 127).mean())
    return dict(частка=round(min(dom if dom else частка_кадру, 1.0), 3),
                кластери=п["сегменти"] if п["придатна"] else [], чому=чому, джерело=джерело,
                світліша=світліша_половина(шлях, м), поверхня=п)


def виміряти_фото(шлях, слот):
    """Фото → (маска-частка, кластери, чому, джерело маски, світліша половина).

    З 2.12 кластери — сегменти поверхні (`поверхня_фото`); кортеж лишився для
    читачів, яким візерунок і позначки не потрібні."""
    в = поверхня_фото(шлях, слот)
    return в["частка"], в["кластери"], в["чому"], в["джерело"], в["світліша"]
