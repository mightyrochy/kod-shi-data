import колір_річ as _КОЛІР
def звести_колір(кластери, слово_моделі, слова_крамниці_):
    """Вимір + слово моделі → основний і другий колір, і `спір`, коли не збігаються.

    Кластер обирається НЕ найбільший, а найбільший У СІМ'Ї ТОНУ, яку назвала
    модель: на фото сукні в руках моделі найбільшим кластером буває тінь або
    підкладка. Коли в сім'ї моделі кластера нема — береться найбільший, і запис
    несе `спір` з обома словами, щоб фід міг лишити слово крамниці.
    """
    if not кластери:
        return None, None, None
    сім_я_моделі = сім_я_слова(слово_моделі) if слово_моделі else None
    у_сім_ї = [к for к in кластери if not _КОЛІР.провенанс_кольору(к) and сім_я_слова(к["слово"]) == сім_я_моделі] if сім_я_моделі else []
    перший = основний = (у_сім_ї or кластери)[0]
    тон_невідомо = not isinstance(основний.get("тон", 0), (int, float))
    if тон_невідомо:
        основний = за_вікном_слова(основний, слова_крамниці_)
        if основний is None:
            return None, None, None
    спір = None
    if слово_моделі and not у_сім_ї and not (тон_невідомо and сім_я_слова(основний["слово"]) == сім_я_моделі):
        спір = dict(вимір=основний["слово"], модель=слово_моделі,
                    сім_я_виміру=сім_я_слова(основний["слово"]), сім_я_моделі=сім_я_моделі,
                    крамниця=(слова_крамниці_ or [None])[0],
                    чому="сім'я тону виміру не збіглася зі словом моделі")
    другий = None
    for к in кластери:
        if к is перший:
            continue
        # другу поверхню судить вимір (`перший`), не точка вікна слова, що могла замінити основний
        if к["частка"] < 0.2 or сім_я_слова(к["слово"]) == сім_я_слова(перший["слово"]):
            continue
        if (_КОЛІР.точка_кольору(перший) is not None and _КОЛІР.точка_кольору(к) is not None
                and _тінь(_КОЛІР.точка_кольору(перший), _КОЛІР.точка_кольору(к))):
            continue
        другий = к
        break
    return основний, другий, спір


def за_вікном_слова(сегмент, слова_крамниці_):
    """Невідомий тон поверхні → інтервал першого відомого слова крамниці.

    Виміряні світлота, хрома й початковий hex маски зберігаються у сегменті.
    Тип забороняє читати його точкою повного кольору. Без слова з вікном — None;
    відомі осі лишаються у поверхні, синтетичний тон не добудовується.
    """
    def вікно(с):
        ім, в, _ = V.вікно_зі_слова(с)
        с_ = (с or "").strip().lower()
        return (ім, в) if ім else ((с_, V.ЛЕКСИКОН[с_]) if с_ in V.ЛЕКСИКОН else (None, None))
    ім, в = next(((і, в_) for с in слова_крамниці_ or [] for і, в_ in [вікно(с)] if і), (None, None))
    if ім is None:
        return None
    # Світлота й хрома лишаються виміряними осями поверхні; тон дає лише слово.
    # Початковий hex з маски зберігається, центр дуги не породжує нового виміру.
    return dict(сегмент, слово=ім, колір_тип="інтервал",
                колір_не_вимір=_КОЛІР.провенанс_кольору(сегмент) or dict(свідок="shop_word", слово=ім, вікно=в,
                    чому="тон поверхні невідомий; світлота і хрома — вимір маски"),
                за_чим="інтервал слова; світлота і хрома — вимір поверхні")


def _тінь(a, b, поріг=8.0, розрив_L=30.0):
    """Чи другий кластер — лише тінь першого, а не другий колір речі.

    Прийом із чужого колірного гейта (`system/gates/color.py`): перед порівнянням
    світлота одного зсувається до іншого — що лишилось, те й є різниця тону і
    хроми. На пробі біла в'язка дала «білий 0.64 + срібний 0.34», і срібний був
    складкою в тіні, а не другим кольором.
    РОЗРИВ СВІТЛОТИ — ВИНЯТОК: біле з чорною вставкою теж має однаковий тон
    (обидва ахроматичні), але це два кольори, а не тінь; при |ΔL| ≥ 30 рішення
    лишається за часткою площі.
    """
    if abs(a[0] - b[0]) >= розрив_L:
        return False
    return CS.de00((b[0], a[1], a[2]), tuple(b)) < поріг


def впевненість(маска_частка, основний, спір, слова_крамниці_, друге_фото_de):
    """Впевненість — ЗІ ЗГОДИ СВІДКІВ, а не з самооцінки моделі.

    V1 питала модель «наскільки ти впевнена» і діставала 0.9 на логотипі. Тут
    четверо свідків, і кожен або згоден, або мовчить: маска (чи є що міряти),
    слово моделі, слово крамниці, друге фото (той самий колір з іншого кадру).
    Свідок, який мовчить, ваги не має — частка рахується від присутніх.
    """
    ваги, бали = [], []
    ваги.append(0.35)
    бали.append(min(1.0, (маска_частка or 0) / 0.25))
    if спір is not None or основний is not None:
        ваги.append(0.25)
        бали.append(0.0 if спір else 1.0)
    if слова_крамниці_:
        ваги.append(0.20)
        сім = {сім_я_слова(с) for с in слова_крамниці_}
        бали.append(1.0 if основний and сім_я_слова(основний["слово"]) in сім else 0.0)
    if друге_фото_de is not None:
        ваги.append(0.20)
        бали.append(1.0 if друге_фото_de <= 5 else (0.5 if друге_фото_de <= 10 else 0.0))
    if основний and not основний.get("у_вікні", True):
        бали = [б * 0.8 for б in бали]
    return round(sum(в * б for в, б in zip(ваги, бали)) / sum(ваги), 2)


def світліша_половина(шлях, маска):
    """Lab, хрома і слово по СВІТЛІШІЙ половині пікселів маски — ОКРЕМИЙ вимір,
    рішення він не міняє (вікна `verify.ЛЕКСИКОН` не чіпаємо).

    ЧОМУ. Тінь на тканині з'їдає хрому: темно-синя річ у півтіні дає
    C* < 8 і лягає у вікно «графіт» чи «чорний», хоча на світлі вона синя. Світліша
    половина пікселів маски — та сама річ при світлі; її хрома каже, чи це справді
    ахроматика, чи темний тон. Число стоїть у записі, щоб проба показала різницю.
    """
    import cv2
    import surface as П
    bgr = читати_bgr(шлях)
    h, w = bgr.shape[:2]
    if маска.shape[:2] != (h, w):
        маска = cv2.resize(маска, (w, h), interpolation=cv2.INTER_NEAREST)
    rgb = [tuple(reversed(p)) for ряд in bgr.tolist() for p in ряд]
    м = [p > 127 for ряд in маска.tolist() for p in ряд]
    rgb, _ = П.поправка_тла(rgb, м, w, h)
    індекси = [i for i, є in enumerate(м) if є]
    if len(індекси) < П.МІНІМУМ:
        return None
    пікс = [CS.to_lab(rgb[i]) for i in індекси]
    медіана = П.перцентиль([p[0] for p in пікс], 50)
    ц = П.середнє([p for p in пікс if p[0] >= медіана])
    L, C_, h = CS.lch(ц)
    сл, у_вікні = слово_з_lab(ц)
    return dict(lab=[round(x, 2) for x in ц], C=round(C_, 1), тон=round(h, 1),
                слово=сл, у_вікні=у_вікні)


# ── ПОВЕРХНЯ (2.12) ─────────────────────────────────────────────────────────
# Вимір поверхні замість однієї точки: сегменти кольору з часткою й розкидом і
# позначки того, що НЕ є кольором речі. Одна модель для всіх класів речей —
# порогів «для темних» чи «для взуття» тут нема.
def виміряти_поверхню(bgr, маска, арр=None, сід=17, джерело=None):
    """Кадр жнив → спільний вимір поверхні; бібліотеки лише масштабують вхід.

    ATR/SAM і запасна маска крамниці передаються різними класами.
    Маска показу сюди не приходить: браузер кличе ядро прямо з RGB.
    """
    import cv2
    import numpy as np
    import surface as П
    h, w = bgr.shape[:2]
    if маска.shape[:2] != (h, w):
        маска = cv2.resize(маска, (w, h), interpolation=cv2.INTER_NEAREST)
    к = min(1.0, П.ДОВГА_СТОРОНА / max(h, w))
    if к < 1:
        розмір = (max(1, round(w*к)), max(1, round(h*к)))
        bgr = cv2.resize(bgr, розмір, interpolation=cv2.INTER_AREA)
        маска = cv2.resize(маска, розмір, interpolation=cv2.INTER_NEAREST)
        h, w = bgr.shape[:2]
    if арр is not None:
        арр = cv2.resize(арр, (w, h), interpolation=cv2.INTER_NEAREST)
    байти = bgr[:, :, ::-1].tobytes()
    rgb = list(zip(байти[::3], байти[1::3], байти[2::3]))
    м = (маска > 127).tobytes()
    шк = np.isin(арр, П.ШКІРА_БЕЗ_ВОЛОССЯ).tobytes() if арр is not None else None
    клас = "запасна" if джерело == "запасна" else "SAM" if джерело and "SAM" in джерело else "ATR"
    return П.виміряти(rgb, w, h, м, клас_маски=клас, мітки_шкіри=шк, сід=сід)


def стиснути_поверхню(п):
    """Поверхня → короткий запис (2.12): {візерунок, придатна, позначки, сегменти, чому}.

    Сегмент — [слово, частка, hex, розкид]: з цього читач бачить, чи колір
    однорідний, а не лише яке він слово."""
    if not п:
        return None
    return dict(візерунок=п["візерунок"], придатна=п["придатна"], чому=п["чому"],
                позначки={к: в for к, в in п["позначки"].items() if в},
                сегменти=[[с["слово"], с["частка"], с["hex"], с["розкид"]] for с in п["сегменти"]])


def поверхня_фото(шлях, слот):
    """Фото → dict(частка, кластери, чому, джерело, світліша, поверхня) — вимір поверхні (2.12).

    `кластери` — сегменти `виміряти_поверхню`, коли поверхня придатна; інакше []
    і колір із фото не міряють — він іде за правилами кольору крамниці, а `чому`
    каже чому. Ключі сегмента ті самі, що в кластерах `виміряти_колір` (слово,
    частка, lab, hex, у_вікні), тож `звести_колір` і читачі їх беруть як є."""
    import cv2
    from жнива_маски import _мітки_atr
    м, dom, чому, джерело = маска_речі(шлях, слот)
    if м is None:
        return dict(частка=0.0, кластери=[], чому=чому, джерело=джерело, світліша=None, поверхня=None)
    try:
        арр = _мітки_atr(шлях)
    except Exception:               # без ATR шкіру не позначимо, а колір виміряємо
        арр = None
    п = виміряти_поверхню(читати_bgr(шлях), м, арр, джерело=джерело)
    if п["поправка"]:
        чому += "; тло біле, експозиція ×%.2f" % п["поправка"]
    чому += "; поверхня: " + п["чому"]
    частка_кадру = float((м > 127).mean())
    return dict(частка=round(min(dom if dom else частка_кадру, 1.0), 3),
                кластери=п["сегменти"] if п["придатна"] else [], чому=чому, джерело=джерело,
                світліша=світліша_половина(шлях, м), поверхня=п)


def виміряти_фото(шлях, слот):
    """Фото → (маска-частка, кластери, чому, джерело маски, світліша половина).

    З 2.12 кластери — сегменти поверхні (`поверхня_фото`); кортеж лишився для
    читачів, яким візерунок і позначки не потрібні."""
    в = поверхня_фото(шлях, слот)
    return в["частка"], в["кластери"], в["чому"], в["джерело"], в["світліша"]
