def ключ(поле, код):
    """Код внутрішньої мови → ключ ядра, або None (unknown, порожньо чи код поза переліком)."""
    if код in (None, "", UNKNOWN) or not isinstance(код, (str, int, float)):
        return None
    return ТАБЛИЦЯ.get(поле, {}).get(str(код).strip())


def код(поле, ключ_ядра):
    """Ключ ядра → код внутрішньої мови, або None — зворотний бік тієї самої таблиці."""
    for к, v in ТАБЛИЦЯ.get(поле, {}).items():
        if v == ключ_ядра:
            return к
    return None


def код_або_невідомо(поле, ключ_ядра):
    """`код`, а ключ поза таблицею — "unknown": значення заяви не несе слова ядра (Ч-2, п.12)."""
    return код(поле, ключ_ядра) or UNKNOWN


def вільний(текст, мова="uk", межа=None):
    """Вільний текст внутрішньою мовою: назва речі чи слово крамниці — дані, а не фраза коду.
    Та сама форма `{free_text, lang}`, що в `РІЧ_КАТАЛОГУ.name` і в заявах Ч-1. `межа` —
    стеля довжини назви в заяві: зріз по межі слова з «…» (картка теж не несе ціле речення
    опису крамниці замість назви)."""
    т = str(текст or "").strip()
    if межа and len(т) > межа:
        т = (т[:межа].rsplit(" ", 1)[0].rstrip(",;:—-(") or т[:межа]) + "…"
    return {"free_text": т, "lang": мова}


