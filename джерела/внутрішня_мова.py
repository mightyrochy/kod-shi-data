def визначення_en(коди):
    """Англійські визначення названих кодів заяв — словник `{код: визначення}` у порядку
    першої появи. Код без визначення не губиться мовчки: він стоїть у словнику з `None`, і
    `тест_протоколу.py` не пускає такого коду в `ЗАЯВИ` (пара мусить бути в обох словниках)."""
    return {к: ЗАЯВИ_EN.get(к) for к in dict.fromkeys(коди)}


def заява(код, **значення):
    """Одна заява повідомлення внутрішньою мовою: `{"code": …}` (+ `"values"`, коли є
    числа чи назви). Коду поза словником не буває — це помилка коду, не «невідомо» для неї."""
    if код not in ЗАЯВИ:
        raise KeyError("заява поза словником ЗАЯВИ: %r" % (код,))
    return dict(code=код, values=значення) if значення else dict(code=код)


def повідомлення(вид, *заяви):
    """Повідомлення жінці внутрішньою мовою: `{"kind": вид, "statements": [заяви]}`.
    Порожній перелік заяв — повідомлення нема (None), і це не тиша: викликач тоді
    нічого не показує, бо казати справді нема чого."""
    if вид not in ВИДИ_ПОВІДОМЛЕНЬ:
        raise KeyError("вид повідомлення поза словником ВИДИ_ПОВІДОМЛЕНЬ: %r" % (вид,))
    з = [x for x in заяви if x]
    return dict(kind=вид, statements=з) if з else None


