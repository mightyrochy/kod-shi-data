# З появою четвертої мети («вище») копії розійшлися б мовчки: форма дала б напрям, а
# колір — ні. Перелік лежить тут, поруч зі словником `goal`, бо це той самий словник
# із іншого боку: які з його значень ПРОСЯТЬ напрям, а які лише міняють вісь уваги.
# «приховати» й «експресія» тут нема навмисно — вони не про гармонізацію, і їхню
# власну знахідку дає `регістр_уваги` (R-CHEV-08).
МЕТИ_З_НАПРЯМОМ = ("лестити", "вище")


def визначення_заяв(коди):
    """Визначення названих кодів заяв — словник `{код: визначення}` у порядку першої появи.
    Словник ЗАЯВ один на обидві моделі (Ч-7, 27.09.2026), тож і функціональна модель, і мовна
    читають ТЕ САМЕ визначення: двох словників, що розійшлися б, не буває. Код без визначення
    не губиться мовчки — він стоїть у словнику з `None`, і `тест_протоколу.py` цього не пускає."""
    return {к: ЗАЯВИ.get(к) for к in dict.fromkeys(коди)}



def заява(код, **значення):
    """Одна заява повідомлення внутрішньою мовою: `{"code": …}` (+ `"values"`, коли є
    числа чи назви). Коду поза словником не буває — це помилка коду, не «невідомо» для неї."""
    if код not in ЗАЯВИ:
        raise KeyError("заява поза словником ЗАЯВИ: %r" % (код,))
    return dict(code=код, values=значення) if значення else dict(code=код)


def повідомлення(вид, *заяви):
    """Повідомлення жінці внутрішньою мовою: `{"kind": вид, "statements": [заяви]}`.
    Порожній перелік заяв — повідомлення нема (None), і це не тиша: викликач тоді
    нічого не показує, бо казати справді нема чого."""
    if вид not in ВИДИ_ПОВІДОМЛЕНЬ:
        raise KeyError("вид повідомлення поза словником ВИДИ_ПОВІДОМЛЕНЬ: %r" % (вид,))
    з = [x for x in заяви if x]
    return dict(kind=вид, statements=з) if з else None


def нота(*частини):
    """Нота слота пулу внутрішньою мовою — ПЕРЕЛІК заяв у порядку появи, або None, коли
    сказати нема чого (Ч-10, рядок 223: `ноти_слотів`). Частина — заява (`{code, values}`),
    перелік заяв або None.

    ЧОМУ ПЕРЕЛІК, А НЕ ОДНА ЗАЯВА. Причин на один слот буває кілька, і вони про РІЗНЕ:
    бажаний метал і ошатність нагоди пояснюють ту саму лічбу пулу, температурні ворота
    стоять до добору, а добір мосту — після. Доти вони зчіплювались у рядок (« · », «; »),
    і кожне нове місце мусило саме не затерти попереднє; перелік знімає це з викликача."""
    вих = []
    for ч in частини:
        if not ч:
            continue
        вих.extend(ч if isinstance(ч, list) else [ч])
    return вих or None


def дописати_ноту(карта, ключ, *частини):
    """Заяви ДОПИСУЮТЬСЯ до ноти, яка вже стоїть у карті `ноти_слотів`, а не затирають її:
    два місця кажуть про один слот (`композитор_збирання` до добору, `міст_пакет` після).
    Віддає ноту слота, яка стала."""
    нова = нота(карта.get(ключ), *частини)
    if нова:
        карта[ключ] = нова
    return карта.get(ключ)


