def ключ(поле, код):
    """Код внутрішньої мови → ключ ядра, або None (unknown, порожньо чи код поза переліком)."""
    if код in (None, "", UNKNOWN) or not isinstance(код, (str, int, float)):
        return None
    return ТАБЛИЦЯ.get(поле, {}).get(str(код).strip())


def код(поле, ключ_ядра):
    """Ключ ядра → код внутрішньої мови, або None — зворотний бік тієї самої таблиці."""
    for к, v in ТАБЛИЦЯ.get(поле, {}).items():
        if v == ключ_ядра:
            return к
    return None


