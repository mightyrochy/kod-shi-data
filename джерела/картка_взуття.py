def ключ(текст):
    """Ім'я чи значення поля так, як його порівнює таблиця: без регістру й зайвих пробілів. Розбір фіду
    (`фід_розбір`) кладе імена `param` малими літерами, а таблицю записано з імен, як їх пише крамниця."""
    return " ".join(str(текст or "").split()).casefold()


ПОЛЯ_ЗА_КЛЮЧЕМ = {ключ(ім): група for ім, група in ПОЛЯ.items()}
ЧИТАННЯ_ЗА_КЛЮЧЕМ = {група: {ключ(з): ч for з, ч in т.items()} for група, т in ЧИТАННЯ.items()}


def група(ім):
    """Група таблиці, до якої належить поле картки, або None."""
    return ПОЛЯ_ЗА_КЛЮЧЕМ.get(ключ(ім))


def прочитати(ім, значення):
    """Читання значення поля з таблиці: {…} (порожнє — «невідомо»), або None — значення в таблиці нема."""
    г = група(ім)
    return None if г is None else ЧИТАННЯ_ЗА_КЛЮЧЕМ[г].get(ключ(значення))


def ознаки(параметри):
    """Що картка каже про пару — поля запису кодами, або {} (нічого не сказано).

    `каблук` — True / False, лише коли поля картки не суперечать одне одному; `каблук_вид`, `каблук_рівень`,
    `підошва_коди`, `сезон_пари`, `підкладка_коди` — списки кодів у порядку переліку, з усіх полів разом;
    `висота_картки` — {см} чи {від, до} і `значення` поля, з якого вона: висота, якої `фід_взуття` числом не
    читає; `картка_не_прочитано` — ознаки, поле про які картка має, а значення поля в таблиці нема."""
    зібрано, є, не_прочитано, висота = {}, set(), set(), None
    for ім, зн in (параметри or {}).items():
        г = група(ім)
        if г is None:
            continue
        значення = " ".join(str(зн or "").split())
        читання = прочитати(ім, значення)
        if читання is None:
            if значення:
                не_прочитано.update(ОЗНАКИ_ГРУПИ[г])
            continue
        if "каблук" in читання:
            є.add(читання["каблук"])
        for ознака in ПЕРЕЛІКИ:
            for код in читання.get(ознака, ()):
                зібрано.setdefault(ознака, set()).add(код)
        if висота is None and "см" in читання:
            висота = dict(см=читання["см"], значення=значення)
        elif висота is None and "смуга" in читання:
            висота = dict(від=читання["смуга"][0], до=читання["смуга"][1], значення=значення)
    вих = {}
    # поле запису речі ← ознака таблиці; поля читає `дріт_моделі.осі` — рядок стилістки. Імена — рядками тут, у
    # петлі, щоб аудит контрактів бачив писача (`audit_contracts`, форма «ключ — змінна петлі»)
    for поле, ознака in (("каблук_вид", "вид"), ("каблук_рівень", "рівень"), ("підошва_коди", "підошва"),
                         ("сезон_пари", "сезон"), ("підкладка_коди", "підкладка")):
        if ознака in зібрано:
            вих[поле] = [к for к in ПЕРЕЛІКИ[ознака] if к in зібрано[ознака]]
    if len(є) == 1:
        вих["каблук"] = є.pop() == "yes"
    if висота:
        вих["висота_картки"] = висота
    if не_прочитано:
        вих["картка_не_прочитано"] = sorted(не_прочитано)
    return вих
