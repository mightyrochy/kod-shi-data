    теплий = _b._hex_lch(42.0, 42.0, 32.0)     # цегляна
    холодний = _b._hex_lch(42.0, 42.0, 342.0)  # сливова
    ряди = [_b.ранг_основ_hex(шк, вл, оч, макіяж={"губи": h})
            for h in (теплий, холодний)]
    однаково = ряди[0] == ряди[1]
