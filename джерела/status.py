    try:
        import os as _os, tempfile as _tf
        import feed as _F, colorspace as _cs, run_outfit as _RO
    except Exception as e:
        return True, "не вдалось порахувати: %s" % e
    шлях = _os.path.join(_tf.gettempdir(), "lex_status.xml")
    with open(шлях, "w", encoding="utf-8") as fh:
        fh.write(_RO._зібрати_xml())
