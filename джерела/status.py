def _тонова_вісь_без_каталогу():
    """Тонова вісь від рис доходить до фільтра й розрізняє людей — і не змінює
    жодного рішення, бо каталог не має чого їй показати.

    Перевірка ВИКОНУВАНА, а не запис: рахує, скільки речей каталогу лежить у
    зоні, де тон може стати останньою звʼязною умовою (кольорові речі з хромою
    вище порогу нейтралі). Доки таких мало, «вісь нічого не змінила» — це факт
    про каталог, а не про вісь, і плутати їх не можна."""
    try:
        import colorspace as cs, outfit as O, run_outfit as RO
    except Exception as e:
        return True, "не вдалось порахувати: %s" % e
    кольорових, усього = 0, 0
    for _арт, _н, _к, _ц, _кол, hexx, _р, _с in RO.МОДЕЛІ:
        усього += 1
        if O.нейтраль(cs.hx(hexx)) is None:
            кольорових += 1
    частка = кольорових / max(1, усього)
    return (частка < 0.5,
            "у каталозі %d кольорових речей із %d (%.0f%%): решта — нейтралі, "
            "яких тонове вікно не судить узагалі. Вісь виміряно окремо, на колі "
            "тонів (measure_hue_reach, розділ B): вона розрізняє двох людей "
            "(Жаккар 0.0–0.29 по слотах). Змінених рішень на цьому каталозі — 0"
            % (кольорових, усього, 100 * частка))


