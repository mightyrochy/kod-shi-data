def _теплова_функція_не_виводиться_з_фіду():
    """Перевірка виконувана й дешева: чи несе бодай один живий фід вагу
    наповнювача, CLO або лофт. Поки не несе — обмеження діє.

    Міряє САМІ ФІДИ, а не наш код: обмеження зникне тоді, коли зʼявляться дані,
    і воно має вміти це помітити без людини.
    """
    import os, feed as Ф
    тут = os.path.dirname(os.path.abspath(__file__))
    маркери = ("fill weight", "грамаж", "clo", "лофт", "г пуху", "вага наповнювача")
    знайдено = []
    # 27.08.2026: живі фіди — вихід жниварки українською (Ager і stolyarchuk у проєкті нема)
