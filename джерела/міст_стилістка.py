def _річ(р):
    """Її річ із паспорта → дріт англійськими ключами: повний опис кодами, без слота (модель сама
    знає, де річ в образі, — власник 24–25.09), колір — словом виміру, коли код міряв (свідок
    сильніший за перше слово моделі), вердикт коду — кодами заяв (означення — раз на виклик у
    `task.statement_codes`), ід і фото — латинкою (`ід_на_дріт`). Lab, hex
    і рамка не їдуть: модель говорить словами, числа — внутрішня шкала коду."""
    о = {"id": _ОО.ід_на_дріт(р["ід"])}
    if р.get("фото"):
        о["photo"] = _ОО.ід_на_дріт(р["фото"])
    if р.get("назва"):
        о["name"] = р["назва"]
    колір = (р.get("вимір") or {}).get("слово") or р.get("колір")
    if колір:
        о["color"] = _РФ.код_поля("color", колір) or колір
    for поле, ключ in (("cut", "крій"), ("length", "довжина"), ("fabric", "матеріал"),
                       ("pattern", "принт"), ("owner", "чия")):
        к = _РФ.код_поля(поле, р.get(ключ))
        if к:
            о[поле] = к
    if р.get("ошатність") is not None:
        о["formality"] = _Д.ошатність_словом(р["ошатність"])   # щабель, не число 1–10 (НГ-3)
    пов = (р.get("вердикт") or {}).get("повідомлення")
    if пов:
        о["verdict"] = {"statements": пов["statements"]}
    if р.get("закріплена") is not None:
        о["in_every_outfit"] = bool(р.get("закріплена"))
    return о


def _випадок(паспорт, сценарій=None):
    """Паспорт випадку → «case» кодами: той самий випадок, що в описі картки (`міст_опис`) і пакеті
    складання; «невідомо» не їде. Без паспорта — порожньо (рядок `без` каже, що нагоди не знаємо)."""
    if not isinstance(паспорт, dict) or not паспорт:
        return {}
    сц = _ПН.з_показу(сценарій, паспорт)[0] if isinstance(сценарій, dict) else None
    в = _Д.випадок(_ПМ.випадок_для_пакета(паспорт, "", сценарій=сц))
    return {к: v for к, v in в.items() if v != _ВМ.UNKNOWN}


def промпт(питання, речі=None, паспорт=None, сценарій=None, фото_речей=None, мова_тексту=None):
    """Промпт моделі: її питання, її речі (коди й вердикт коду), випадок кодами паспорта, які фото
    прикріплено до яких речей. Фото без речі в паспорті не згадується."""
    речі = [р for р in речі or [] if isinstance(р, dict) and р.get("ід")]
    за_фото = {р.get("фото"): р.get("ід") for р in речі if р.get("фото")}
    дані = dict(question=str(питання or "").strip(),
                items=[_річ(р) for р in речі],
                photos=[dict(photo=_ОО.ід_на_дріт(ф), item=_ОО.ід_на_дріт(за_фото[ф]))
                        for ф in фото_речей or [] if ф in за_фото],
                case=_випадок(паспорт, сценарій))
    return _json.dumps(_ЗП.зібрати(ПИТАННЯ, дані, мова_тексту=мова_тексту), ensure_ascii=False)


def прийняти(відповідь):
    """Сира відповідь моделі → dict(відповідь, причина): уся відповідь — текст (форма «plain text»);
    JSON з полем `answer` (як доти) — текст цього поля. Проза з дужками чи огорожею ```
    — не відповідь: це уривок JSON, і жінці він не йде."""
    сира = str(відповідь or "").strip()
    if сира and "{" not in сира and "```" not in сира:
        return dict(відповідь=сира, причина=None)
    об, чому_не, _ = _ПР.розбір_останній(сира, ("answer",))
    т = об.get("answer") if isinstance(об, dict) else None
    if isinstance(т, str) and т.strip():
        return dict(відповідь=т.strip(), причина=None)
    # ПРИЧИНА — КОДОМ: вона їде в запис виклику й діагноз звіту власника, не жінці
    return dict(відповідь="", причина=("empty" if not сира else "no_answer_field" if isinstance(об, dict)
                                        else "not_json_object: %s" % чому_не))


def стилістка(вхід):
    """Ендпойнт моста `стилістка` (два кроки, див. шапку модуля)."""
    d = _json.loads(вхід) if isinstance(вхід, str) else (вхід or {})
    if d.get("відповідь_моделі") is not None:
        return _json.dumps(прийняти(d["відповідь_моделі"]), ensure_ascii=False)
    if not str(d.get("питання") or "").strip():
        return _json.dumps(dict(помилка="нема питання"), ensure_ascii=False)
    return _json.dumps(dict(промпт=промпт(d["питання"], d.get("речі"), d.get("паспорт"), d.get("сценарій"),
                                          d.get("фото_речей"), d.get("мова_тексту"))), ensure_ascii=False)
