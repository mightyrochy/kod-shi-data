_ГРУПИ_ДОВІДНИКА = {"occasion": ("нагоди", False), "place": ("місця", True)}


def _коди_довідника(поле):
    """«коди: <код> (<підпис плитки>[: <нота>]), …» — коди поля з підписами довідника ядра."""
    import паспорт_нагоди as _ПН
    група, з_нотою = _ГРУПИ_ДОВІДНИКА[поле]
    рядки = {р["ключ"]: р for р in _ПН.довідник()[група]}
    вих = []
    for код, ключ in _ВМ.ТАБЛИЦЯ[поле].items():
        р = рядки.get(ключ) or {}
        визн = str(р.get("підпис") or "").strip() + (": %s" % р["нота"] if з_нотою and р.get("нота") else "")
        вих.append("%s (%s)" % (код, визн) if визн else код)
    return "коди: " + ", ".join(вих)


