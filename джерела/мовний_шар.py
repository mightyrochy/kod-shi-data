    # МЕЖІ — ТІ, ЩО ПОЧУВ ПЕРЕКЛАДАЧ: гейт слів (`вето_тверде`) без слів мовчить і зняв би їх
    слоти = dict((досі.get("вето_тверде") or {}).get("слоти") or {}, **нові_слоти)
