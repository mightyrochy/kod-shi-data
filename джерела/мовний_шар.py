    # ПОЯСНЕННЯ МОВНОЇ МОДЕЛІ СТИЛІСТЦІ (НП-в6): нове замінює давнє, хід без нього лишає давнє —
    # як `подія`. Код його не читає: воно їде стилістці (`пакет_моделі.випадок_для_пакета`).
    пояснення = _текст(в.get("stylist_note")) or _текст(досі.get("пояснення_мови"))
    if пояснення:
        п["пояснення_мови"] = пояснення
    if вигадки:
        п["не_взято_кодом"] = list(п.get("не_взято_кодом") or []) + вигадки
    if подія_без_смуги:
        п["не_взято_кодом"] = list(п.get("не_взято_кодом") or []) + [
            "event_without_scene · event=%s · required=event_place · verdict_vs_occasion=no_input"
            % _json_.dumps(_текст(в.get("event"))[:60], ensure_ascii=False)]
    # ТЕМИ ПОРАДИ — ЗІ СТАНУ ПІСЛЯ ЦЬОГО ХОДУ. Виклик 0 пропонував теми в промпті, тобто за
    # станом ДО її слів; тут стан уже відомий (театр о 18:00 — вечір), і вечірні теми йдуть
    # на цьому ж ході. Без повторів (п.9): уже запропоновані лежать у `поради_дані`.
    # ОБОВʼЯЗКОВЕ ПИТАННЯ — БЕЗ ПОРАДИ НА ТОМУ САМОМУ ХОДІ (Ч-5): порада каже «відповідати не
    # мусиш, образи зберуться й так», а обовʼязкове — «без цього не зберуться». Разом це
    # неправда в одній репліці (стенд, «концерт» без коду: «Скажи, куди ти йдеш: без цього
    # образи не зберуться… образи зберу й так»). Теми не губляться: у `поради_дані` вони не
    # лягають і прийдуть на першому ході, де сценарій уже є.
    обовʼязкове = [] if _СЦ.є_сценарій(_СЦ.з_показу(сценарій or {}, п)[0]) else (
        ["event_place"] if _ПН.подія_названа(п) else ["occasion"])
    дані = list(досі.get("поради_дані") or [])
    драп_поради = dict(досі.get("драп_сирий") or {}, **(драп or {})) or None
    if частини is not None:
        дозволені = [к for к in (_ВМ.код("advice_topic", т) for т in _ПН.теми_дозволені(
            сценарій or {}, dict(п, поради_дані=дані), драп=драп_поради,
            є_річ=bool(фото or п.get("речі_з_фото")))) if к]
        текст, теми, відкинуто, бракує = суд_частин(частини, дозволені, обовʼязкове)
        п["поради_дані"] = дані + [_ВМ.ключ("advice_topic", т) for т in теми]
        п["розмову_вела"] = "мовна модель"
        return dict(паспорт=п, теми_поради=теми, обовʼязкове=обовʼязкове, записано=в, вигадки=вигадки,
                    текст=текст, відкинуто=відкинуто, бракує_обовʼязкового=бракує, дозволені=дозволені)
    # ХТО ВІВ РОЗМОВУ (М-5, пункт B7 чекліста) не губиться, коли шов перезбирає паспорт без нових слів
    # (плитки перед збиранням, `паспортШаромП`): останній хід розмови склала мовна модель
    if досі.get("розмову_вела"):
        п["розмову_вела"] = досі["розмову_вела"]
    порада = None if обовʼязкове else _ПН.порада_коду(
        сценарій or {}, dict(п, поради_дані=дані), "",
        драп=драп_поради, є_річ=bool(фото or п.get("речі_з_фото")))
