"""МОВНИЙ ШАР: модель-перекладачка між функціональними моделями та інтерфейсом.

РІШЕННЯ ВЛАСНИКА 25.09.2026 (дослівно): «Модель, спеціаліст з української мови, просто
робить весь текст, що бачить людина, природним. Вона сама не приймає жодних рішень, не
відповідає на питання, не обробляє інформацію і не збирає образи. Це перекладач. Вся
українська, що бачить людина, іде від неї. Але це лише прослойка між функціональними
моделями та інтерфейсом.» Того ж дня: «Зараз мова і всі проблеми з її розумінням і
інтерпретацією віддані спеціалізованій моделі. Всі інші костилі не потрібні. <…> Якщо
цей варіант не буде давати потрібну точність, тоді вже будемо допрацьовувати рішення.»

ДЕ ШОВ. Одна точка на виході до інтерфейсу — `показ.html: мовоюП`: туди зміст приходить
готовим (репліка стилістки, тексти картки, підпис приміряння), звідти — на екран. Код
тут лише будує промпт (`розмітити`, `промпт`) і читає відповідь (`прийняти`); змісту він
не судить. Точність перекладу видно у звіті власника — на кожен виклик шару там стоїть
вхід, вихід, модель і час, — а міряє її ноутбук (`проби/мова_шару_вимір.py`).

ТЕКСТ БЕЗ ВІДПОВІДІ лишається вхідним: збій моста, відповідь не JSON чи пропущений номер —
жінка бачить те, що склали код і моделі, а причина йде в запис виклику.

БЕЗ МОДЕЛІ ШАРУ ВСЕ ЯК ДОТИ: показ не кличе цей модуль, текст іде на екран тим самим
шляхом, що до 25.09.
"""
import json as _json_
import re

import протокол as _ПР

# Промпт — лише роль, вхід, форма відповіді й межа (правило власника 25.09: «максимально
# зрозумілим і чітким, тільки по ділу»): жодних прикладів-фраз і пояснень для людей.
ПРОМПТ_ВИХОДУ = """Ти — перекладачка в застосунку-стилістці. Ти пишеш природною українською тексти, які зараз побачить жінка. Рішень не приймаєш, на питання не відповідаєш, змісту не міняєш.

Вхід — JSON-масив [{"н": номер, "текст": текст}]: тексти, які склали код та інші моделі.

Відповідь — лише JSON-об'єкт {"<н>": "<текст>"} для кожного н зі входу: той самий зміст природною українською; до жінки — на «ти»; стилістка про себе — у жіночому роді; текст, що вже природний, — без змін.

ТЕКСТИ:
"""


def розмітити(тексти):
    """[{н, ключ, текст}] з `тексти` ([{ключ, текст}] або {ключ: текст}): лише
    непорожні тексти з літерами, номери — з 1, у порядку входу."""
    пари = list(тексти.items()) if isinstance(тексти, dict) else \
        [(т.get("ключ"), т.get("текст")) for т in (тексти or []) if isinstance(т, dict)]
    вих = []
    for ключ, текст in пари:
        т = str(текст or "").strip()
        if not re.search(r"[^\W\d_]", т):
            continue
        вих.append(dict(н=len(вих) + 1, ключ=str(ключ), текст=т))
    return вих


def промпт(розмітка):
    """Промпт моделі шару: роль і форма + JSON текстів, по одному на рядок."""
    return ПРОМПТ_ВИХОДУ + "[\n" + ",\n".join(
        _json_.dumps(dict(н=р["н"], текст=р["текст"]), ensure_ascii=False) for р in розмітка) + "\n]"


_ЛАПКИ_КРАЇ = (("«", "»"), ('"', '"'), ("“", "”"))


def _без_обгортки(вихід, вхід):
    """Текст моделі без лапок навколо ВСЬОГО тексту, яких не було у вході."""
    т = str(вихід or "").strip()
    for л, п in _ЛАПКИ_КРАЇ:
        if len(т) > 1 and т.startswith(л) and т.endswith(п) and not str(вхід).strip().startswith(л):
            return т[len(л):-len(п)].strip()
    return т


def прийняти(розмітка, відповідь):
    """Відповідь моделі шару → dict(тексти={ключ: текст}, без_відповіді=[ключі], причина).

    Кожен текст, який модель повернула, стає тим, що бачить жінка. Текст, якого вона не
    повернула (відповідь не JSON, номера нема, значення порожнє), лишається вхідним і
    стоїть у `без_відповіді` з причиною — мовчки не губиться нічого."""
    об, чому_не = _ПР.розбір(str(відповідь or ""))
    if об is None:                  # `протокол.розбір` бере лише об'єкт; масив дочитується тут
        try:
            об = _json_.loads(re.sub(r"^```(?:json)?\s*|\s*```$", "", str(відповідь or "").strip()))
        except ValueError:
            об = None
    # МАСИВ ЗАМІСТЬ ОБ'ЄКТА — та сама відповідь іншою формою: рядки в порядку текстів або
    # {н, текст}. Читається, лише коли однозначно (рядків рівно стільки, скільки текстів)
    if isinstance(об, list):
        if all(isinstance(x, dict) and "н" in x for x in об):
            об = {str(x["н"]): x.get("текст") for x in об}
        elif len(об) == len(розмітка or []) and all(isinstance(x, str) for x in об):
            об = {str(р["н"]): x for р, x in zip(розмітка, об)}
    тексти, без = {}, []
    for р in розмітка or []:
        вих = об.get(str(р["н"])) if isinstance(об, dict) else None
        if isinstance(вих, (list, tuple)):
            вих = " ".join(str(x) for x in вих)
        if isinstance(вих, str) and вих.strip():
            тексти[р["ключ"]] = _без_обгортки(вих, р["текст"])
        else:
            тексти[р["ключ"]] = р["текст"]
            без.append(р["ключ"])
    причина = None
    if без:
        причина = ("відповідь не JSON (%s)" % чому_не if not isinstance(об, dict)
                   else "модель не повернула текстів: %d з %d" % (len(без), len(розмітка or [])))
    return dict(тексти=тексти, без_відповіді=без, причина=причина)


def мова(вхід):
    """Ендпойнт моста `мова`, два кроки (як `паспорт`):
      · без `відповідь_моделі` — {промпт, розмітка}: промпт моделі шару й розмітка, яку
        показ віддає назад на другому кроці (Python між кроками стану не тримає — чотири
        картки йдуть паралельно);
      · з `відповідь_моделі` — `прийняти(розмітка, відповідь_моделі)`.
    Вхід першого кроку: `тексти` ({ключ: текст} або [{ключ, текст}])."""
    d = _json_.loads(вхід) if isinstance(вхід, str) else (вхід or {})
    if d.get("відповідь_моделі") is not None:
        return _json_.dumps(прийняти(d.get("розмітка") or [], d.get("відповідь_моделі")),
                            ensure_ascii=False)
    р = розмітити(d.get("тексти") or {})
    return _json_.dumps(dict(промпт=(промпт(р) if р else ""), розмітка=р), ensure_ascii=False)
