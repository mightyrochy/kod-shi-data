def _заяви_словником(вжиті):
    """Рядки «- код — визначення.» для заяв, які цього разу приїхали (порядок — словника)."""
    return ["- %s — %s." % (к, _ВМ.ЗАЯВИ[к]) for к in _ВМ.ЗАЯВИ if к in вжиті]


# ── КОДИ У ЗНАЧЕННЯХ ЗАЯВ ТЕЖ ПОТРІБНО ВИЗНАЧИТИ (наряд Ч-6, 27.09.2026, п.12) ──
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. `values` заяви — така сама внутрішня мова, як і сам код заяви:
# `slots: ["bag"]`, `anchor: "eyes"`, `look_level: "high"`. Доти промпт ніс визначення
# ЗАЯВ і жодного визначення цих кодів, а рядок форми казав «числа й назви з values пиши
# як вони є» — тобто просив модель поставити жінці на картку слово «bag». Стенд цього не
# ловив: його заглушка перекладала коди СВОЄЮ копією таблиці, якої в живої моделі нема
# (знімок #401, «колір мали нести ці слоти образу — сумка» — «сумка» там від заглушки).
# Тепер у промпті стоять визначення РІВНО тих кодів, що приїхали, і взяті вони з тієї
# самої `ТАБЛИЦЯ`, якою шов перекладає вхід, — другого словника в системі не заводиться.
# Число, hex і слово крамниці кодами не є (у таблиці їх нема) і лишаються як є.
# ОДИН КОД У КІЛЬКОХ ПОЛЯХ (`knee` — і довжина, і рівень тіла) віддає обидва слова через
# «/»: контекст заяви в моделі є, а мовчазно вибрати за неї одне поле код не може.
def _коди_значень(значення, знайдені):
    """Рекурсивно: усі рядки в `значення`, які є кодами `ВМ.ТАБЛИЦЯ`, → {код: слова}."""
    if isinstance(значення, dict):
        for v in значення.values():
            _коди_значень(v, знайдені)
    elif isinstance(значення, (list, tuple)):
        for v in значення:
            _коди_значень(v, знайдені)
    elif isinstance(значення, str):
        слова = sorted({м[значення] for м in _ВМ.ТАБЛИЦЯ.values() if значення in м})
        if слова:
            знайдені[значення] = " / ".join(w.replace("_", " ") for w in слова)


def _коди_словником(заяви):
    """Рядки «- код — слова.» для кодів, ужитих у `values` цих заяв; порожньо — нема рядків.

    Стоять ПЕРЕД словником заяв: коди значень і коди заяв живуть у різних переліках, і
    якщо колись зіткнуться іменем, останнє слово має лишитись за визначенням заяви."""
    знайдені = {}
    for з in заяви or []:
        if isinstance(з, dict):
            _коди_значень(з.get("values") or {}, знайдені)
    return (["", "КОДИ У ЗНАЧЕННЯХ:"] + ["- %s — %s." % (к, знайдені[к]) for к in sorted(знайдені)]
            ) if знайдені else []


