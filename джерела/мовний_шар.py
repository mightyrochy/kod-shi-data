# кодом `<рід>_generic` (`print_generic`, `dress_generic`, `bag_generic`, `scarf_generic`, `jewelry_generic`), а
# голого `print` чи `dress` у них нема. «Без принта» перекладач коментаря записав `reasons: ["heels", "print"]`:
