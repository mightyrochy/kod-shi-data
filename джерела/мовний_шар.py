# ЯКЩО СТИЛІСТКА ВЖЕ НАЗВАЛА КОЛІР РЕЧІ, ДРУГОЇ НАЗВИ НЕ БУДЕ (рядок 4104; ЖИВІ-17 №11–13). Руки 3–4 пишуть
# «color #E6DCCD (warm oat)», «color #ffffff pure white», «Emerald velvet dress … in color #043d22», і код кольору
# давав другу назву: «колір білий чистий білий», «кольору білого (теплого вівсяного)», «Смарагдово-зелена … кольору
# хвойний» — правило «лиши її слово» тримав лише промпт шару, і п'ять разів не втримав. Тепер такий hex знімається
# без коду, і лишається її слово. Її слово — дужки одразу за hex або назва кольору внутрішньої мови (`color_name`:
# коди й частини складених, синоніми написання) у тому ж реченні, що й hex; речення кінчається на «.», «!», «?»
# перед пробілом чи кінцем, або на новому рядку. Колір без назви («color #043d22 made from heavy fabric» без
# «emerald» у реченні, «color #059669, fabric: silk») іде кодом, як доти.
_СИНОНІМИ_КОЛЬОРУ = {"gray": "grey", "silver": "silvery", "gold": "golden", "pearl": "pearly", "ivory": "cream",
                     "charcoal": "graphite"}
_КІНЕЦЬ_РЕЧЕННЯ = re.compile(r"[.!?](?:\s|$)|\n")


def _слова_кольору():
    """Слова назв кольору внутрішньої мови: коди `color_name` (і частини складених) та синоніми написання."""
    ч = set(_СИНОНІМИ_КОЛЬОРУ)
    for к in _ВМ.ТАБЛИЦЯ.get("color_name", {}):
        ч.add(к)
        ч.update(к.split("_"))
    return ч


def _колір_названо(текст, поч, кін):
    """Чи hex у `текст[поч:кін]` має в тому ж реченні її власну назву кольору (див. вище)."""
    після, перед = текст[кін:], текст[:поч]
    дужки = re.match(r"\s*\(([^()\n]*)\)", після)
    if дужки and re.search(r"[^\W\d_]", дужки.group(1)):
        return True
    речення = _КІНЕЦЬ_РЕЧЕННЯ.split(перед)[-1] + " " + _КІНЕЦЬ_РЕЧЕННЯ.split(після)[0]
    слова = _слова_кольору()
    return any(т.lower() in слова for т in re.findall(r"[A-Za-z]+", речення))


def кольори_кодом(текст):
    """Текст із hex → той самий текст, де кожен hex (з ярликом і дужками) — «[colour: <код>]» або нічого.
    Hex, біля якого вже стоїть її назва кольору, знімається без коду (`_колір_названо`)."""
    def код(м):
        if _колір_названо(м.string, м.start(), м.end()):
            return ""
        к = _код_кольору(м.group(1) or м.group(2))
        return "[colour: %s]" % к if к else ""
    if not _HEX_У_ТЕКСТІ.search(str(текст or "")):
        return текст
    return re.sub(r"[ \t]{2,}", " ", _HEX_У_ТЕКСТІ.sub(код, str(текст or ""))).replace(" ,", ",")


def _абзац_кольорів(розмітка):
    """Абзац промпту про коди кольорів у текстах — лише вжиті коди з внутрішнім словом ядра; без них — ""."""
    коди = sorted({к for р in розмітка for к in _КОД_КОЛЬОРУ.findall(р["текст"])})
    if not коди:
        return ""
    return ("[colour: код] у тексті — колір речі кодом: напиши на його місці українську назву цього кольору, "
            "узгоджену з реченням. Коли та сама річ у тексті вже має колір своїм словом, лиши її слово, а "
            "другої назви кольору не додавай. Коди: "
            + "; ".join("%s — %s" % (к, _ВМ.ключ("color_name", к)) for к in коди) + ".\n\n")


def розмітити(тексти, виправ=None):
    """[{н, ключ, текст}] з `тексти` ([{ключ, текст}] або {ключ: текст}): лише
    непорожні тексти з літерами, номери — з 1, у порядку входу. `виправ` — {ключ: [слова]}
    (ПРОЗА-1): текст ключа вже переклала модель, і в ньому лише ці слова не кирилицею — вони
    їдуть у промпт поруч із текстом (`виправ`), щоб повтор правив їх, а не перекладав усе."""
    пари = list(тексти.items()) if isinstance(тексти, dict) else \
        [(т.get("ключ"), т.get("текст")) for т in (тексти or []) if isinstance(т, dict)]
    вих = []
    for ключ, текст in пари:
        т = кольори_кодом(str(текст or "").strip()).strip()
        if not re.search(r"[^\W\d_]", т):
            continue
        р = dict(н=len(вих) + 1, ключ=str(ключ), текст=т)
        слова = [str(с) for с in ((виправ or {}).get(str(ключ)) or []) if str(с).strip()]
        if слова:
            р["виправ"] = list(dict.fromkeys(слова))
        вих.append(р)
    return вих


def промпт(розмітка):
    """Промпт моделі шару: роль і форма (з кодами кольорів, коли вони є в текстах) + JSON текстів, по одному на рядок."""
    основа, _, хвіст = ПРОМПТ_ВИХОДУ.rpartition("ТЕКСТИ:\n")
    return основа + _абзац_кольорів(розмітка) + "ТЕКСТИ:\n" + хвіст + "[\n" + ",\n".join(
        _json_.dumps(dict(н=р["н"], текст=р["текст"], **({"виправ": р["виправ"]} if р.get("виправ") else {})),
                     ensure_ascii=False) for р in розмітка) + "\n]"


_ЛАПКИ_КРАЇ = (("«", "»"), ('"', '"'), ("“", "”"))


def _без_обгортки(вихід, вхід):
    """Текст моделі без лапок навколо ВСЬОГО тексту, яких не було у вході."""
    т = str(вихід or "").strip()
    for л, п in _ЛАПКИ_КРАЇ:
        if len(т) > 1 and т.startswith(л) and т.endswith(п) and not str(вхід).strip().startswith(л):
            return т[len(л):-len(п)].strip()
    return т


