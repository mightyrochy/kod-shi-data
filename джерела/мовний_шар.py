def _тип(с):
    """Коротко, яке значення чекає поле: коди з переліку, число, вільний текст, об'єкт, список.

    БЕЗ ЗАГЛУШОК (М-2, вада 3 живого прогону 26.09): доти вільний текст описувався шаблоном
    `{"free_text": "…", "lang": "<мова>"}`, і мала модель переписувала його як є — `"lang":
    "<мова>"` у кожній відповіді, а в пробі 2 MamayLM дописала за тим самим взірцем 13
    своїх: `"quote": "<уривок її слів про спідницю, слово в слово>"`. Тепер форма значення —
    лише словами, без жодного рядка-заглушки: вільний текст — рядок її мовою (обгортку
    `free_text`/`lang` ставить код), «unknown» — пропущене поле (межа промпта)."""
    if "enum" in с:
        return "коди: " + ", ".join(к for к in с["enum"] if к != U)
    if _ref(с) == "free_text":
        return "рядок її мовою"
    if _ref(с) in _ОБʼЄКТИ:
        return "об'єкт " + _ОБʼЄКТИ[_ref(с)][0]
    if с.get("type") == "array":
        return ("список (до %d)" % с["maxItems"] if с.get("maxItems") else "список") + "; елемент — " \
            + _тип(с.get("items") or {})
    if с.get("type") == "object" and с.get("properties"):
        return "об'єкт {" + "; ".join("%s — %s" % (к, _тип(v)) for к, v in с["properties"].items()) + "}"
    if с.get("type") == "object" and isinstance(с.get("additionalProperties"), dict):
        return "об'єкт: ключ — назва поля, значення — уривок її слів"
    if с.get("type") in ("number", "integer"):
        межі = [x for x in (с.get("minimum"), с.get("maximum")) if x is not None]
        return ("ціле" if с["type"] == "integer" else "число") + (" %s–%s" % tuple(межі) if len(межі) == 2 else "")
    if с.get("type") == "string":
        return "рядок" + (" #rrggbb" if "#" in str(с.get("pattern") or "") else "")
    if "oneOf" in с:
        return " або ".join(_тип(в) for в in с["oneOf"] if в.get("const") != U)
    return "значення"


