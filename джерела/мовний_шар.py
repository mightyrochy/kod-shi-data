def _річ_з_пари(x):
    """Річ, написана парою {quote, value: {ознаки}}, → річ {quote, ознаки}: уривок той самий,
    ознаки ті самі — форма не вбиває зміст, а уривок лишається своїм у кожної речі."""
    знач = next((x[к] for к in _ЗНАЧЕННЯ_ПАРИ if isinstance(x, dict) and isinstance(x.get(к), dict)), None)
    return dict(знач, quote=знач.get("quote") or x.get("quote")) if знач is not None else x


def _пара(поле, с, v):
    """(значення, цитата) поля `поле` зі схемою `с` з відповіді перекладача.

    Пара {quote, value} → значення й уривок (замість value модель може назвати ключ `code`
    чи саме поле); об'єкт-поле (formality, makeup) з quote поміж своїх ознак → ознаки й
    уривок; вільний текст, написаний самим quote, — цей текст; список пар → значення списком
    і уривки разом (різні уривки разом тримаються, лише коли вона сказала їх підряд — сторож
    не слабшає). Список речей не розгортається: у кожної речі свій quote. Решта — як є."""
    речі = с.get("type") == "array" and _ref(с.get("items") or {}) in _ОБʼЄКТИ
    if isinstance(v, dict) and any(к in v for к in _ЗНАЧЕННЯ_ПАРИ + (поле,)):
        return next(v[к] for к in _ЗНАЧЕННЯ_ПАРИ + (поле,) if к in v), v.get("quote")
    if речі:
        return ([_річ_з_пари(x) for x in v] if isinstance(v, list) else v), None
    if not (isinstance(v, (dict, list)) and v):
        return v, None
    if isinstance(v, dict):
        if "quote" not in v:
            return v, None
        решта = {к: x for к, x in v.items() if к != "quote"}
        return (решта or (v["quote"] if _вільний(с) else None)), v["quote"]
    if not all(isinstance(x, dict) and ("quote" in x or any(к in x for к in _ЗНАЧЕННЯ_ПАРИ)) for x in v):
        return v, None
    пари = [_пара(поле, (с.get("items") or {}) if с.get("type") == "array" else с, x) for x in v]
    цитати = list(dict.fromkeys(str(ц).strip() for _, ц in пари if isinstance(ц, str) and not _порожнє(ц)))
    значення = [з for з, _ in пари]
    return (значення[0] if len(значення) == 1 and с.get("type") != "array" else значення), (" ".join(цитати) or None)


def прийняти_вхід(вид, відповідь, ід_речей=None):
    """Відповідь вхідного перекладача → dict(внутрішня, незнайомі, невідомо, заглушки, причина).

    `внутрішня` — лише поля з опорою (unknown і порожнє не пишуться): так код і звіт
    бачать рівно те, що перекладач почув. Пари {quote, value} (вид із `пари`) розгортаються
    в поле і його уривок у `quotes` — внутрішня мова та сама, що доти. Не JSON — порожня
    внутрішня мова з причиною: жінка лишається зі своїм сценарієм, а не з вигаданим.
    `заглушки` — шляхи незаповнених заглушок у відповіді (звіт власника). `ід_речей` — речі
    образу для коментаря: річ з id поза ними не вигадується, а стоїть у `незнайомі`."""
    об, чому_не = _обʼєкт(відповідь)
    if not isinstance(об, dict):
        return dict(внутрішня={}, незнайомі=[], невідомо=[], заглушки=[],
                    причина="відповідь не JSON-об'єкт (%s)" % (чому_не or type(об).__name__))
    в = ВИДИ_ВХОДУ[вид]
    поля, незнайомі, невідомо = в["поля"], [], []
    внутрішня, цитати = {}, {}
    for к, v in об.items():
        if к not in поля:
            незнайомі.append(к)
            continue
        ц = None
        if в.get("пари") and к != "quotes":
            v, ц = _пара(к, поля[к], v)
        було = len(незнайомі)
        н = _норм(поля[к], v, к, незнайомі)
        if н not in (None, [], {}):
            внутрішня[к] = н
            if ц is not None and not _порожнє(ц) and к not in _БЕЗ_ЦИТАТИ:
                цитати[к] = " ".join(map(str, ц)) if isinstance(ц, list) else str(ц).strip()
        elif len(незнайомі) == було:   # перекладач сам сказав «unknown» (чи порожньо) — у звіт
            невідомо.append(к)
    if цитати:                          # уривок пари стоїть поруч із полем — він і тримає поле
        внутрішня["quotes"] = dict(внутрішня.get("quotes") or {}, **цитати)
    if ід_речей is not None and внутрішня.get("about_items"):
        незнайомі += ["about_items.id=%s" % р["id"] for р in внутрішня["about_items"] if р["id"] not in ід_речей]
        внутрішня["about_items"] = [р for р in внутрішня["about_items"] if р["id"] in ід_речей]
        if not внутрішня["about_items"]:
            del внутрішня["about_items"]
    return dict(внутрішня=внутрішня, незнайомі=незнайомі, невідомо=невідомо, заглушки=_заглушки(об), причина=None)


