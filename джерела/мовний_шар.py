def мова(вхід):
    """Ендпойнт моста `мова`. Кожен виклик моделі шару — два кроки (як `паспорт`):
    спершу промпт, потім відповідь моделі. Python між кроками стану не тримає.
      · {тексти} → {промпт, розмітка, вибірка}; {розмітка, відповідь_моделі} → `прийняти`;
      · {розмова: {нове, історія}, сценарій, паспорт?, фото?, профіль?} → {промпт, вибірка};
        {розмова, відповідь_моделі} → `прийняти_розмову` (М-5: хід розмови одним викликом);
      · {вхід: вид, слова, контекст?} → {промпт, вибірка}; {вхід, відповідь_моделі} → `прийняти_вхід`;
      · {коментар_з: внутрішня мова коментаря до образу, паспорт?} → `паспорт_з_коментаря`
        (С-2: межі й бажання коментаря — у паспорт сценарію, відкинуті речі — у «не ця»);
      · {паспорт_з: внутрішня, сценарій, вето?, паспорт?, драп_сирий?, фото_речей?,
        речі_з_фото?, слова_ходу?, слова_розмови?, частини?} → `паспорт_з_шару` + рядки випадку
        (з `частини` — ще й суд частин ходу розмови: `текст`, `відкинуто`, `бракує_обовʼязкового`);
      · {репліка} → {промпт, вибірка}; {репліка, відповідь_моделі} → `прийняти_репліку`;
      · {повідомлення} → {промпт, розмітка, незнайомі, вибірка}; {розмітка_повідомлень,
        відповідь_моделі} → `прийняти_повідомлення`.
    `вибірка` — поля вибірки моделі для тіла виклику шару (`ВИБІРКА`)."""
    d = _json_.loads(вхід) if isinstance(вхід, str) else (вхід or {})
    дамп = lambda x: _json_.dumps(x, ensure_ascii=False, default=str)
    if d.get("розмова") is not None:
        if d.get("відповідь_моделі") is not None:
            return дамп(прийняти_розмову(d["відповідь_моделі"]))
        return дамп(dict(промпт=промпт_розмови(d), вибірка=ВИБІРКА))
    if d.get("вхід"):
        речі = [р for р in d.get("речі") or [] if isinstance(р, dict) and р.get("id")]
        if d.get("відповідь_моделі") is not None:
            return дамп(прийняти_вхід(d["вхід"], d["відповідь_моделі"],
                                      ід_речей=({str(р["id"]) for р in речі} if "речі" in d else None)))
        контекст = d.get("контекст")
        if речі:     # речі образу для коментаря — кодами, id для точного посилання
            контекст = dict(контекст or {}, items=[dict(
                id=str(р["id"]), slot=_ВМ.код("slot", р.get("слот")) or U,
                name={"free_text": str(р.get("назва") or ""), "lang": "uk"}) for р in речі])
        return дамп(dict(промпт=промпт_входу(d["вхід"], d.get("слова"), контекст), вибірка=ВИБІРКА))
    if d.get("коментар_з") is not None:
        return дамп(паспорт_з_коментаря(d["коментар_з"],
                                        паспорт_досі=(d.get("паспорт") if isinstance(d.get("паспорт"), dict) else None)))
    if d.get("паспорт_з") is not None:
        import паспорт_нагоди as _ПН
        р = паспорт_з_шару(d["паспорт_з"], d.get("сценарій") or {}, d.get("вето"),
                           паспорт_досі=(d.get("паспорт") if isinstance(d.get("паспорт"), dict) else None),
                           драп=(d.get("драп_сирий") or None), фото=(d.get("фото_речей") or None),
                           речі_з_фото=d.get("речі_з_фото"),
                           слова_ходу=(d.get("слова_розмови") or d.get("слова_ходу") or ""),
                           частини=(d.get("частини") if isinstance(d.get("частини"), dict) else None))
        return дамп(dict(р, випадок=_ПН.паспорт_рядком(р["паспорт"]),
                         випадок_людині=_ПН.паспорт_рядком_людині(р["паспорт"]),
                         # ШМАТКИ З КЛЮЧАМИ — поруч із рядком (Л-9): показ вішає піктограму
                         # на ключ поля, а не на позицію шматка (п.12).
                         випадок_шматки=_ПН.паспорт_шматками_людині(р["паспорт"])))
    if d.get("репліка") is not None:
        if d.get("відповідь_моделі") is not None:
            return дамп(прийняти_репліку(d["відповідь_моделі"]))
        return дамп(dict(промпт=промпт_репліки(d["репліка"]), вибірка=ВИБІРКА))
    if d.get("розмітка_повідомлень") is not None:
        return дамп(прийняти_повідомлення(d["розмітка_повідомлень"], d.get("відповідь_моделі")))
    if d.get("повідомлення") is not None:
        р = розмітити_повідомлення(d["повідомлення"])
        return дамп(dict(промпт=(промпт_повідомлень(р) if р else ""), розмітка=р,
                         незнайомі=незнайомі_заяви(d["повідомлення"]), вибірка=ВИБІРКА))
    if d.get("відповідь_моделі") is not None:
        return дамп(прийняти(d.get("розмітка") or [], d.get("відповідь_моделі")))
    р = розмітити(d.get("тексти") or {}, d.get("виправ") if isinstance(d.get("виправ"), dict) else None)
    return дамп(dict(промпт=(промпт(р) if р else ""), розмітка=р, вибірка=ВИБІРКА))
