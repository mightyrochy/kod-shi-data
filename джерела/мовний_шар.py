# ЩО ЦЕ МІНЯЄ В РІШЕННІ. `values` заяви — така сама внутрішня мова, як і сам код заяви:
# `slots: ["bag"]`, `anchor: "eyes"`, `look_level: "high"`. Доти промпт ніс визначення
