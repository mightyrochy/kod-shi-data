_ЗНАЧЕННЯ_ПАРИ = ("value", "code")


def _вільний(с):
    """Чи поле — вільний текст її мовою (рядок чи список рядків), а не код і не число."""
    с = (с.get("items") or {}) if с.get("type") == "array" else с
