def розмітити(тексти):
    """[{н, ключ, текст}] з `тексти` ([{ключ, текст}] або {ключ: текст}): лише
    непорожні тексти з літерами, номери — з 1, у порядку входу."""
    пари = list(тексти.items()) if isinstance(тексти, dict) else \
        [(т.get("ключ"), т.get("текст")) for т in (тексти or []) if isinstance(т, dict)]
    вих = []
    for ключ, текст in пари:
        т = str(текст or "").strip()
        if not re.search(r"[^\W\d_]", т):
            continue
        вих.append(dict(н=len(вих) + 1, ключ=str(ключ), текст=т))
    return вих


def промпт(розмітка):
    """Промпт моделі шару: роль і форма + JSON текстів, по одному на рядок."""
    return ПРОМПТ_ВИХОДУ + "[\n" + ",\n".join(
        _json_.dumps(dict(н=р["н"], текст=р["текст"]), ensure_ascii=False) for р in розмітка) + "\n]"


_ЛАПКИ_КРАЇ = (("«", "»"), ('"', '"'), ("“", "”"))


def _без_обгортки(вихід, вхід):
    """Текст моделі без лапок навколо ВСЬОГО тексту, яких не було у вході."""
    т = str(вихід or "").strip()
    for л, п in _ЛАПКИ_КРАЇ:
        if len(т) > 1 and т.startswith(л) and т.endswith(п) and not str(вхід).strip().startswith(л):
            return т[len(л):-len(п)].strip()
    return т


# «▁» (U+2581, SentencePiece) Lapa ставить у власну відповідь замість пробілів, зокрема відступом
# перед ключами, і ламає ним JSON (Н-1, 26.09: той самий прийом, що `каталог_розбір.ВСТАВКА`, і
# лише так вимір ноутбука мірив зміст, а не токенізатор). Тут вона стає пробілом: поза рядком
# JSON це відступ, у рядку — пробіл між її словами (уривок звіряється без зайвих пробілів).
_ВСТАВКА = "▁"


# НЕДІЙСНИЙ ЕКРАН У РЯДКУ JSON (П-3; Н-1, 26.09, MamayLM, картка руки 3): модель написала
# «\н» — кириличну «н» на місці «n» екрана переводу рядка, — і вся відповідь не розбиралась:
# п'ять перекладених текстів картки лишились внутрішньою мовою. «\н» — це «\n»; перед
# іншим знаком, який не є екраном JSON, зворотна риска знімається. Пари «\\» регулярка
# бере цілими, тож буквальна риска перед «н» лишається рискою.
_ЕКРАН = re.compile(r"\\(.)", re.S)


def _екрани(т):
    """Текст відповіді з недійсними екранами JSON, полагодженими так, як сказано вище."""
    return _ЕКРАН.sub(lambda м: "\\n" if м.group(1) == "н"
                      else м.group(0) if м.group(1) in '"\\/bfnrtu' else м.group(1), т)


def _обʼєкт(відповідь, нотатки=None):
    """(JSON-об'єкт або масив із відповіді моделі, причина, коли не вийшло).

    Недійсний екран лагодиться (`_екрани`), лише коли суворий розбір не вдався; що так
    прочитано, дописується в `нотатки`, коли їх дали, — у запис виклику шару, не мовчки."""
    сир = str(відповідь or "").replace(_ВСТАВКА, " ")      # «▁» Lapa — пробіл (М-2)
    об, чому_не = _ПР.розбір(сир)
    if об is None and _екрани(сир) != сир:
        об, _ = _ПР.розбір(_екрани(сир))
        if об is not None:
            сир = _екрани(сир)
            if нотатки is not None:
                нотатки.append("недійсний екран у JSON прочитано («\\н» — як «\\n»)")
    if об is None:                  # `протокол.розбір` бере лише об'єкт; масив дочитується тут
        for т in dict.fromkeys((сир, _екрани(сир))):
            try:
                об = _json_.loads(re.sub(r"^```(?:json)?\s*|\s*```$", "", т.strip()))
                break
            except ValueError:
                об = None
    return об, чому_не


ФОРМА_ВХОДУ = "текст у полі вхідної форми ({н, текст} чи {n, text}) прочитано"


def _з_форми(x):
    """Обʼєкт вхідної форми {н, текст} → (н, текст); ті самі ключі англійською теж: MamayLM
    26.09 повернула на кожен номер {"n": 1, "text": "…"} (П-3), і шість перекладів картки
    лишались внутрішньою мовою. Не та форма — (None, None)."""
    if not isinstance(x, dict):
        return None, None
    н = next((x[к] for к in ("н", "n") if к in x), None)
    return н, next((x[к] for к in ("текст", "text") if isinstance(x.get(к), str)), None)


def прийняти(розмітка, відповідь):
    """Відповідь моделі шару → dict(тексти={ключ: текст}, без_відповіді=[ключі], причина,
    нотатки=[що прочитано з неідеальної форми]).

    Кожен текст, який модель повернула, стає тим, що бачить жінка. Текст, якого вона не
    повернула (відповідь не JSON, номера нема, значення порожнє), лишається вхідним і
    стоїть у `без_відповіді` з причиною — мовчки не губиться нічого."""
    нотатки = []
    об, чому_не = _обʼєкт(відповідь, нотатки)
    # МАСИВ ЗАМІСТЬ ОБ'ЄКТА — та сама відповідь іншою формою: рядки в порядку текстів або
    # {н, текст}. Читається, лише коли однозначно (рядків рівно стільки, скільки текстів)
    if isinstance(об, list):
        пари = [_з_форми(x) for x in об]
        if all(н is not None for н, _ in пари):
            об = {str(н): т for н, т in пари}
        elif len(об) == len(розмітка or []) and all(isinstance(x, str) for x in об):
            об = {str(р["н"]): x for р, x in zip(розмітка, об)}
    тексти, без = {}, []
    for р in розмітка or []:
        вих = об.get(str(р["н"])) if isinstance(об, dict) else None
        if isinstance(вих, dict) and _з_форми(вих)[1] is not None:
            вих = _з_форми(вих)[1]
            if ФОРМА_ВХОДУ not in нотатки:
                нотатки.append(ФОРМА_ВХОДУ)
        if isinstance(вих, (list, tuple)):
            вих = " ".join(str(x) for x in вих)
        if isinstance(вих, str) and not _ВМ.невідомо(вих):   # "null" / "None" — не текст для неї
            тексти[р["ключ"]] = _без_обгортки(вих, р["текст"])
        else:
            тексти[р["ключ"]] = р["текст"]
            без.append(р["ключ"])
    причина = None
    if без:
        причина = ("відповідь не JSON (%s)" % чому_не if not isinstance(об, dict)
                   else "модель не повернула текстів: %d з %d" % (len(без), len(розмітка or [])))
    return dict(тексти=тексти, без_відповіді=без, причина=причина, нотатки=нотатки)


