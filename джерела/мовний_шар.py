    # ПЕРЕКОНАННЯ СЛОВАМИ ЯДРА (K-LNG-04): шов кладе їх у вимоги з «не спростовувати»
    переконання = [ф for ф in list(досі.get("переконання") or []) + [_фраза(р) for р in в.get("beliefs") or []]
                   if ф and ф not in знято_б]
    if переконання:
        п["переконання"] = list(dict.fromkeys(переконання))
    if бажання_коди:
        п["бажання_коди"] = бажання_коди
    п["перекладено_шаром"] = True
    # РЕШТА СКАЗАНОГО (М-1, В-5): те, що не лягло в жодне поле, не гине — їде моделям рядком
    # випадку (`паспорт_нагоди.паспорт_рядком`), її мовою, з позначкою
    решта = [_текст(x) for x in list(досі.get("решта") or []) + [в.get("rest")]]
