_ОБʼЄКТИ = {"thing": ("«річ»", _ВМ.РІЧ_У_СЛОВАХ), "own_item": ("«її річ»", _ВМ.ЇЇ_РІЧ)}


def _ref(с):
    """Ім'я означення зі `$ref` (#/$defs/<ім'я>) або None."""
    р = (с or {}).get("$ref") or ""
    return р.rsplit("/", 1)[-1] if р else None


def _тип(с):
    """Коротко, яке значення чекає поле: коди з переліку, число, вільний текст, об'єкт, список."""
    if "enum" in с:
        return "коди: " + ", ".join(к for к in с["enum"] if к != U)
    if _ref(с) == "free_text":
        return 'вільний текст {"free_text": "…", "lang": "<мова>"}'
    if _ref(с) in _ОБʼЄКТИ:
        return "об'єкт " + _ОБʼЄКТИ[_ref(с)][0]
    if с.get("type") == "array":
        return "список; елемент — " + _тип(с.get("items") or {})
    if с.get("type") == "object" and с.get("properties"):
        return "об'єкт {" + "; ".join("%s — %s" % (к, _тип(v)) for к, v in с["properties"].items()) + "}"
    if с.get("type") in ("number", "integer"):
        межі = [x for x in (с.get("minimum"), с.get("maximum")) if x is not None]
        return ("ціле" if с["type"] == "integer" else "число") + (" %s–%s" % tuple(межі) if len(межі) == 2 else "")
    if с.get("type") == "string":
        return "рядок" + (" #rrggbb" if "#" in str(с.get("pattern") or "") else "")
    if "oneOf" in с:
        return " або ".join(_тип(в) for в in с["oneOf"] if в.get("const") != U) + ' або "unknown"'
    return "значення"


def промпт_входу(вид, слова, контекст=None):
    """Промпт вхідного перекладача: роль, вхід, поля схеми з кодами, межа «unknown»."""
    в = ВИДИ_ВХОДУ[вид]
    рядки = [в["роль"], "", "Вхід — %s." % в["вхід"], "",
             "Відповідь — лише JSON-об'єкт із полями нижче. Чого в її словах нема — \"unknown\" "
             "або поля не пиши; порожній список — такого не сказано. Не вигадуй і не виводь одне "
             "поле з іншого. Лише коди з переліків.", "", "Поля:"]
    рядки += ["- %s — %s; %s" % (ім, с.get("description", ""), _тип(с)) for ім, с in в["поля"].items()]
    вже = {}
    for ім, (назва, поля) in _ОБʼЄКТИ.items():
        if any(ім in _json_.dumps(с) for с in в["поля"].values()):
            рядки += ["", "Об'єкт %s — лише названі ознаки:" % назва]
            for к, с in поля.items():   # поле, уже описане в попередньому об'єкті, не повторюється
                рядки.append("- %s — %s; %s" % (к, с.get("description", ""),
                             ("коди ті самі, що в %s" % вже[к]) if вже.get(к) and "enum" in с else _тип(с)))
                вже.setdefault(к, назва)
    рядки += ["", "СЛОВА:", str(слова or "").strip()]
    if контекст:
        рядки += ["", "КОНТЕКСТ:", _json_.dumps(контекст, ensure_ascii=False)]
    return "\n".join(рядки)


def _код(v):
    """Код у формі переліку: без пробілів по краях, нижній регістр, пробіл → «_»."""
    return re.sub(r"[\s-]+", "_", str(v).strip().lower()) if isinstance(v, str) else v


def _норм(с, v, шлях, незнайомі):
    """Значення за описом поля схеми → внутрішня мова або None (unknown / нема).

    ФОРМА НЕ ВБИВАЄ ЗМІСТ (Т-13): рядок там, де схема чекає список, стає списком з одного;
    рядок там, де чекає вільний текст, — текстом її мови. Код поза переліком не
    підставляється сусіднім — стає None, і шлях до нього йде в `незнайомі` (звіт власника)."""
    if v is None or (isinstance(v, str) and (not v.strip() or _код(v) == U)):
        return None
    if _ref(с) == "free_text":
        if isinstance(v, dict) and str(v.get("free_text") or "").strip():
            return {"free_text": str(v["free_text"]).strip(), "lang": str(v.get("lang") or "uk")}
        return {"free_text": v.strip(), "lang": "uk"} if isinstance(v, str) else None
    if _ref(с) in _ОБʼЄКТИ:
        return _норм({"type": "object", "properties": _ОБʼЄКТИ[_ref(с)][1]}, v, шлях, незнайомі)
    if "enum" in с:
        if _код(v) in с["enum"]:
            return _код(v)
        незнайомі.append("%s=%s" % (шлях, v))
        return None
    if с.get("type") == "array":
        сп = v if isinstance(v, list) else [v]
        вих = []
        for і, x in enumerate(сп):
            н = _норм(с.get("items") or {}, x, "%s[%d]" % (шлях, і), незнайомі)
            if н is not None and н not in вих:
                вих.append(н)
        return вих[:с["maxItems"]] if с.get("maxItems") else вих
    if с.get("type") == "object" and с.get("properties"):
        if isinstance(v, list) and len(v) == 2 and set(с["properties"]) == {"from", "to"}:
            v = {"from": v[0], "to": v[1]}
        if not isinstance(v, dict):
            незнайомі.append("%s=%s" % (шлях, v))
            return None
        вих = {}
        for к, x in v.items():
            if к not in с["properties"]:
                незнайомі.append("%s.%s" % (шлях, к))
                continue
            н = _норм(с["properties"][к], x, "%s.%s" % (шлях, к), незнайомі)
            if н not in (None, []):
                вих[к] = н
        бракує = [к for к in (с.get("required") or []) if к not in вих]
        return None if (not вих or бракує) else вих
    if с.get("type") in ("number", "integer"):
        try:
            ч = float(str(v).replace(",", ".").replace("−", "-").replace("°", "").strip())
        except ValueError:
            незнайомі.append("%s=%s" % (шлях, v))
            return None
        if (с.get("minimum") is not None and ч < с["minimum"]) or (с.get("maximum") is not None and ч > с["maximum"]):
            незнайомі.append("%s=%s" % (шлях, v))
            return None
        return int(round(ч)) if с["type"] == "integer" else ч
    if с.get("type") == "string":
        т = str(v).strip()
        if с.get("pattern") and not re.match(с["pattern"], т):
            незнайомі.append("%s=%s" % (шлях, v))
            return None
        return т
    if "oneOf" in с:
        for в in с["oneOf"]:
            if в.get("const") == U:
                continue
            зайве = []
            н = _норм(в, v, шлях, зайве)
            if н is not None:
                return н
        незнайомі.append("%s=%s" % (шлях, v))
        return None
    return None


def прийняти_вхід(вид, відповідь, ід_речей=None):
    """Відповідь вхідного перекладача → dict(внутрішня, незнайомі, причина).

    `внутрішня` — лише поля з опорою (unknown і порожнє не пишуться): так код і звіт
    бачать рівно те, що перекладач почув. Не JSON — порожня внутрішня мова з причиною:
    жінка лишається зі своїм сценарієм, а не з вигаданим. `ід_речей` — речі образу для
    коментаря: річ з id поза ними не вигадується, а стоїть у `незнайомі`."""
    об, чому_не = _обʼєкт(відповідь)
    if not isinstance(об, dict):
        return dict(внутрішня={}, незнайомі=[], причина="відповідь не JSON-об'єкт (%s)" % (чому_не or type(об).__name__))
    поля, незнайомі = ВИДИ_ВХОДУ[вид]["поля"], []
    внутрішня = {}
    for к, v in об.items():
        if к not in поля:
            незнайомі.append(к)
            continue
        н = _норм(поля[к], v, к, незнайомі)
        if н not in (None, [], {}):
            внутрішня[к] = н
    if ід_речей is not None and внутрішня.get("about_items"):
        незнайомі += ["about_items.id=%s" % р["id"] for р in внутрішня["about_items"] if р["id"] not in ід_речей]
        внутрішня["about_items"] = [р for р in внутрішня["about_items"] if р["id"] in ід_речей]
        if not внутрішня["about_items"]:
            del внутрішня["about_items"]
    return dict(внутрішня=внутрішня, незнайомі=незнайомі, причина=None)


