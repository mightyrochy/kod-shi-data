# ══ ВИХІД: ПОВІДОМЛЕННЯ ВНУТРІШНЬОЮ МОВОЮ → ТЕКСТИ ЕКРАНА (Ч-1, CLAUDE.md п.12) ══
# Те саме, що `промпт_репліки` робить для розмови, — для картки образу й екрана
# «Палітра»: код віддає вид повідомлення й заяви кодами, речення складає модель.
# ЧОМУ ОДИН ВИКЛИК НА ВСІ ПОВІДОМЛЕННЯ КАРТКИ. Той самий розрахунок, що в `розмітити`:
# картка має до десятка рядків, і десять викликів моделі на одну картку — десять
# затримок і десять шансів не відповісти. Промпт несе визначення ЛИШЕ тих видів і
# заяв, які цього разу приїхали, тож він не росте зі словником.
ПРОМПТ_ПОВІДОМЛЕНЬ = "Ти — перекладачка в застосунку-стилістці. Ти пишеш природною українською " \
    "рядки, які зараз побачить жінка на екрані: до неї — на «ти», стилістка про себе — у жіночому " \
    "роді. Рішень не приймаєш, на питання не відповідаєш, від себе нічого не додаєш і не радиш."


def розмітити_повідомлення(повідомлення):
    """[{н, ключ, вид, заяви}] з `повідомлення` ({ключ: повідомлення} або [{ключ, ...}]):
    лише ті, що мають вид зі `ВИДИ_ПОВІДОМЛЕНЬ` і хоч одну заяву; номери — з 1."""
    пари = list(повідомлення.items()) if isinstance(повідомлення, dict) else \
        [(п.get("ключ"), п) for п in (повідомлення or []) if isinstance(п, dict)]
    вих = []
    for ключ, п in пари:
        if not isinstance(п, dict) or п.get("kind") not in _ВМ.ВИДИ_ПОВІДОМЛЕНЬ:
            continue
        з = [x for x in (п.get("statements") or [])
             if isinstance(x, dict) and x.get("code") in _ВМ.ЗАЯВИ]
        if з:
            вих.append(dict(н=len(вих) + 1, ключ=str(ключ), вид=п["kind"], заяви=з))
    return вих


def незнайомі_заяви(повідомлення):
    """Коди заяв і видів, яких у словниках нема: мовчки не губиться нічого (той самий
    принцип, що `незнайомі` на вході) — вони стоять у записі виклику й у звіті."""
    пари = list(повідомлення.values()) if isinstance(повідомлення, dict) else (повідомлення or [])
    погані = []
    for п in пари:
        if not isinstance(п, dict):
            continue
        if п.get("kind") not in _ВМ.ВИДИ_ПОВІДОМЛЕНЬ:
            погані.append("вид:%s" % п.get("kind"))
        погані += ["заява:%s" % з.get("code") for з in (п.get("statements") or [])
                   if isinstance(з, dict) and з.get("code") not in _ВМ.ЗАЯВИ]
    return sorted(set(погані))


def промпт_повідомлень(розмітка):
    """Промпт перекладачки повідомлень: роль, форма, визначення ЛИШЕ вжитих видів і
    заяв, тоді самі повідомлення внутрішньою мовою."""
    види = [в for в in _ВМ.ВИДИ_ПОВІДОМЛЕНЬ if any(р["вид"] == в for р in розмітка)]
    вжиті = {з.get("code") for р in розмітка for з in р["заяви"]}
    return "\n".join([
        ПРОМПТ_ПОВІДОМЛЕНЬ, "",
        "Вхід — JSON-масив об'єктів із ключами н (номер), вид (вид рядка) і заяви — список об'єктів "
        "із ключами code (що сказано) і values (числа й назви до цієї заяви).",
        "На кожен номер — ОДИН текст: одне-два речення, які передають усі його заяви разом, у "
        "порядку заяв. Не перелік і не список. Кодів у тексті не пиши — пиши їхній зміст. Числа, "
        "hex і слова крамниці з values пиши як вони є; значення, що стоїть у «КОДИ У ЗНАЧЕННЯХ», "
        "— це теж код: пиши його слова звідти, а не сам код.", "",
        "ВИДИ РЯДКІВ:"] + ["- %s — %s." % (в, _ВМ.ВИДИ_ПОВІДОМЛЕНЬ[в]) for в in види] + (
        _коди_словником([з for р in розмітка for з in р["заяви"]])) + [
        "", "ЗАЯВИ:"] + _заяви_словником(вжиті) + [
        "", "Відповідь — лише JSON-об'єкт: ключ — номер н кожного повідомлення зі входу, значення — "
        "його текст.", "",
        "ПОВІДОМЛЕННЯ:",
        "[\n" + ",\n".join(_json_.dumps(dict(н=р["н"], вид=р["вид"], заяви=р["заяви"]),
                                        ensure_ascii=False) for р in розмітка) + "\n]"])


def прийняти_повідомлення(розмітка, відповідь):
    """Відповідь перекладачки повідомлень → dict(тексти={ключ: текст}, без_відповіді, причина).

    ЗАПАСНОГО ТЕКСТУ СЛОВАМИ КОДУ НЕМА (п.12, як у `прийняти_репліку`): ключ, на який
    модель не відповіла, у `тексти` не потрапляє взагалі — показ тоді не малює рядка, а
    причина стоїть у записі виклику й у звіті власника. Вигадати за неї фразу код не може:
    саме цього п.12 і не дозволяє. Форму відповіді дочитує так само, як `прийняти` (П-3):
    збитий екран і текст у вхідній формі {n, text} — з `нотатки`, не мовчки."""
    нотатки = []
    об, чому_не = _обʼєкт(відповідь, нотатки)
    if isinstance(об, list):
        пари = [_з_форми(x) for x in об]
        if all(н is not None for н, _ in пари):
            об = {str(н): т for н, т in пари}
        elif len(об) == len(розмітка or []) and all(isinstance(x, str) for x in об):
            об = {str(р["н"]): x for р, x in zip(розмітка, об)}
    тексти, без = {}, []
    for р in розмітка or []:
        вих = об.get(str(р["н"])) if isinstance(об, dict) else None
        if isinstance(вих, dict) and _з_форми(вих)[1] is not None:
            вих = _з_форми(вих)[1]
            if ФОРМА_ВХОДУ not in нотатки:
                нотатки.append(ФОРМА_ВХОДУ)
        if isinstance(вих, (list, tuple)):
            вих = " ".join(str(x) for x in вих)
        if isinstance(вих, str) and вих.strip() and not _ВМ.невідомо(вих):
            тексти[р["ключ"]] = _без_обгортки(вих, "")
        else:
            без.append(р["ключ"])
    причина = None
    if без:
        причина = ("відповідь не JSON (%s)" % чому_не if not isinstance(об, dict)
                   else "модель не повернула текстів: %d з %d" % (len(без), len(розмітка or [])))
    return dict(тексти=тексти, без_відповіді=без, причина=причина, нотатки=нотатки)


