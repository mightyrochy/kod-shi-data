def прийняти_репліку(відповідь):
    """Відповідь перекладача репліки → dict(текст, причина). Текст — ЛИШЕ з поля `text`
    (урок #310: чужий текст приносить у чат примітки й міркування моделі)."""
    об, чому_не = _обʼєкт(відповідь)
    т = об.get("text") if isinstance(об, dict) else None
    if isinstance(т, str) and not _ВМ.невідомо(т):
        return dict(текст=т.strip(), причина=None)
    return dict(текст="", причина=("text — «невідомо» (%s)" % _json_.dumps(т, ensure_ascii=False)
                                   if isinstance(т, str) and т.strip() else "нема поля text") if isinstance(об, dict)
                else "відповідь не JSON-об'єкт (%s)" % (чому_не or type(об).__name__))


def текст_кодом(репліка, випадок_людині=""):
    """Запасна репліка словами КОДУ, коли перекладач репліки не відповів: жінка не лишається
    без відповіді, а в записі виклику стоїть причина."""
    import паспорт_нагоди as _ПН
    р = репліка or {}
    рядки = [т["free_text"] for т in р.get("code_lines") or [] if isinstance(т, dict)]
    if isinstance(р.get("answer"), dict):
        рядки.append(р["answer"].get("free_text") or "")
    if р.get("recorded"):
        рядки.append("Записала" + (": " + випадок_людині if випадок_людині else "") + ".")
    if р.get("required"):
        рядки.append("Скажи, куди ти йдеш: без нагоди чи місця образи не зберуться.")
    рядки.append(_ПН.порада_кодом([_ВМ.ключ("advice_topic", т) for т in р.get("advice_topics") or []]))
    return "\n".join(x for x in рядки if x) or "Записала."


