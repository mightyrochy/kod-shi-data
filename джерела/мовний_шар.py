# Доти шов віддавав `паспорт_з_json` порожні слова, і гейти опори main (`сказано_про`,
# `місце_зі_слів`) на порожньому тексті мовчали = пропускали: `place=office_corporate,
# hour=7, temperature_c=30` без жодної опори ставали паспортом. Звіряли ж ці факти ті самі
# читачі її слів у коді (`_вигадки`: словники чисел, місць, реєстрів) — мова в коді, проти
# аудит/ПРОДУКТ.md п.12. Тепер перекладач сам називає, на чому стоїть кожне поле (`quotes`, `quote`
# речі), а код звіряє лише одне — що цей уривок справді є в її словах ходу (механіка
# `цитата_тримає` з #311: підрядок, без словника). Поле без такої цитати в паспорт не йде,
# і це видно рядком формату #309 у `не_взято_кодом` і в записі виклику шару.
# `reserved_colour` і `open_zones` (НП-в) — норма події, яку модель розуміє з події, як ошатність:
# гостя на весіллі не каже «біле не моє», а храм не каже «плечі закрити» — цитати нема й не буде.
# `part_of_day` (НП-в5, рядок 522 (3)) — так само: «Офіційний вечір» — плитка, а не її слова, і
# вечір у назві події модель розуміє тим самим ходом; години (`hour`) це не стосується — число
# лише з її слів.
_БЕЗ_ЦИТАТИ = ("event", "place_words", "mood", "question", "question_about", "rest", "quotes", "formality",
               "reserved_colour", "open_zones", "part_of_day", "stylist_note", "minute")
_РЕЧІ_З_ЦИТАТОЮ = ("wants", "vetoes", "retract", "own_items", "beliefs")


def _до_звірки(текст):
    """Текст для звірки цитати: нижній регістр, один апостроф, розділові знаки — пробілом."""
    т = str(текст or "").lower().replace("’", "'").replace("ʼ", "'").replace("`", "'")
    return " ".join(re.sub(r"[^\w']+", " ", т).split())


def цитата_тримає(цитата, слова):
    """Чи дослівний уривок `цитата` стоїть у її словах `слова` (регістр, лапки, розділові
    знаки й пробіли не важать). Порожня цитата чи без жодної літери й цифри — не тримає;
    цитата з самих чисел — лише цілими числами («6» не тримається її «16:00»)."""
    ц, т = _до_звірки(цитата), _до_звірки(слова)
    if not re.search(r"[^\W_]", ц):
        return False
    if not re.search(r"[^\W\d_]", ц):
        return (" %s " % ц) in (" %s " % т)
    return ц in т


def вигадка_рядком(поле, сказала, цитата, зробив="not_taken"):
    """Рядок звіту про поле мовної моделі без опори в її словах — будова #309 (відрізки через « · »,
    поле — третім), але КОДАМИ (рядок 168, п.12): `invented · step=layer · field=<поле> · model_said=<json>
    · quote=<уривок>|none · quote_in_her_words=no · code=<що зробив код>`. Після «=» — лише сирі дані."""
    return ("invented · step=layer · field=%s · model_said=%s · quote=%s · quote_in_her_words=no · code=%s"
            % (поле, _json_.dumps(сказала, ensure_ascii=False),
               _json_.dumps(str(цитата), ensure_ascii=False) if цитата else "none", зробив))


def невзяте_рядком(поле, сказала):
    """Рядок звіту про поле ходу, яке код прочитав як «невідомо» (рядок 3191: `goal_zones: "none"` губилось
    без сліду) — будова `вигадка_рядком`, кодами: `unknown_value · step=layer · field=<поле> ·
    model_said=<json> · code=not_taken`."""
    return ("unknown_value · step=layer · field=%s · model_said=%s · code=not_taken"
            % (поле, _json_.dumps(сказала, ensure_ascii=False)))


def _тримається(в, слова):
    """Внутрішня мова ходу → (лише поля й речі, чия цитата стоїть у її словах; рядки звіту).

    Вільний текст (подія, настрій, питання, решта) — сам її слова й цитати не потребує; смуга
    події (`event_formality`) тримається подією. Без її слів ходу (паспорт кодом із порожньою
    дельтою) звіряти нема чого — і перекладу там нема.
    `слова` — рядок (її слова ходу) або СПИСОК її реплік розмови (М-5): модель розмови ставить
    поле й на її слові з попередньої репліки («ні, краще темніше» знімає бежеву сукню з першої),
    і уривок тоді тримається, коли стоїть дослівно в будь-якій ОДНІЙ її репліці — не на стику двох."""
    if not isinstance(в, dict) or not в:
        return {}, []
    if isinstance(слова, (list, tuple)):
        репліки = [str(с or "") for с in слова]
        цитата_тримає_ = lambda ц, _с: any(цитата_тримає(ц, с) for с in репліки)
    else:
        цитата_тримає_ = цитата_тримає
    цитати, вих, рядки = dict(в.get("quotes") or {}), {}, []
    for к, v in в.items():
        if к in _РЕЧІ_З_ЦИТАТОЮ:
            лишити = []
            for і, р in enumerate(v or []):
                ц = р.get("quote") or ((р.get("name") or {}).get("free_text") if к == "own_items" else None) \
                    or цитати.get(к)
                if цитата_тримає_(ц, слова):
                    лишити.append(р)
                else:
                    рядки.append(вигадка_рядком("%s[%d]" % (к, і), {x: y for x, y in р.items() if x != "quote"}, ц))
            if лишити:
                вих[к] = лишити
        elif к in _БЕЗ_ЦИТАТИ or цитата_тримає_(цитати.get(к), слова):
            вих[к] = v
        else:
            рядки.append(вигадка_рядком(к, v, цитати.get(к)))
    return вих, рядки


def паспорт_з_шару(внутрішня, сценарій, вето_чипів=None, паспорт_досі=None, драп=None, фото=None,
                   речі_з_фото=None, слова_ходу="", частини=None, контраст=None, не_взято=None):
    """Внутрішня мова одного ходу → паспорт ядра, теми поради й обов'язкове.

    ДЕЛЬТА, А НЕ ПОВНИЙ ПАСПОРТ: перекладач переказує лише цей хід. Чого він не почув —
    лишається з паспорта досі; списки (бажання, межі, реєстри) доливаються, а те, від
    чого вона відмовилась (`retract`), знімається.
    ОДИН ПАРСЕР: паспорт збирає `паспорт_нагоди.паспорт_з_json` — той самий, що для
    виклику 0, — але слова йому не йдуть: читачам її слів (словник заперечень, опора
    числа й місця, реєстр зі слів) нема чого читати, і вони мовчать; межі тримаються
    ті, що почув перекладач (`вето_тверде` з них, без гейта слів). Функціональним
    моделям її сирі слова не їдуть (`слова` паспорта порожнє): лише структура — і вона
    несе все речення: подію зі смугою, решту сказаного (`решта`), поля на цитатах.
    СТОРОЖ (М-1, В-4): поле без цитати в `слова_ходу` не береться (`_тримається`).
    `речі_з_фото` — опис речей із фото від моделі з зором (виклик 0 без її слів).
    ХІД РОЗМОВИ (М-5): `частини` — частини відповіді моделі розмови (`прийняти_розмову`), а
    `слова_ходу` — список УСІХ її реплік розмови (сторож тримає поле на будь-якій із них). Теми
    поради тоді обирала модель, і код їх СУДИТЬ (`суд_частин`) на стані після ходу — замість того,
    щоб обирати сам (`порада_коду`); у `поради_дані` лягають лише теми, до яких справді запрошено."""
    import паспорт_нагоди as _ПН
    import сценарій as _СЦ
    в, вигадки = _тримається(внутрішня, слова_ходу)
    # ЇЇ РІЧ БЕЗ СТАНУ — НЕ ЗАПИСАНА (рядок 4102, живі 17 №4). «Взуття — замшеві чоботи» модель дала в `own_items` без
    # `status` (у схемі він обов'язковий): річ трималась цитатою, але не ставала ні закріпленою, ні знятою — звіт казав
    # «не закріплено: мовний шар: None», а репліка «Записала: …» про неї мовчала. Чи буде річ в образі, вирішує мовна
    # модель (п.17), а не код: річ без стану шов знімає з ходу як не записану — рядком `не_взято_кодом` кодами, і поле
    # `own_items` стає в `not_recorded`, тож репліка каже їй, що цього не записано.
    без_стану = [р for р in в.get("own_items") or [] if _ВМ.ключ("own_item_status", р.get("status")) is None]
    if без_стану:
        лишити = [р for р in в["own_items"] if not any(р is б for б in без_стану)]
        в = dict({к: x for к, x in в.items() if к != "own_items"}, **({"own_items": лишити} if лишити else {}))
        не_взято = list(не_взято or []) + [
            "own_item_without_status · step=layer · field=own_items · model_said=%s · code=not_taken"
            % _json_.dumps(_текст(р.get("quote")) or _текст(р.get("name")), ensure_ascii=False) for р in без_стану]
    # остання її репліка — «слова ходу» для уривків мети й наміру, коли цитати нема
    слова_ходу = (слова_ходу[-1] if слова_ходу else "") if isinstance(слова_ходу, (list, tuple)) else слова_ходу
    досі = паспорт_досі if isinstance(паспорт_досі, dict) else {}
    джерела_досі = досі.get("джерело_полів") if isinstance(досі.get("джерело_полів"), dict) else {}
    є = lambda x: x not in (None, "", "невідомо", [], {})
    об = {}
    for поле, ім in _ПРОСТІ:
        к = _ВМ.ключ(поле, в.get(поле))
        # «щоденне», яке код підставив під її річ з фото, — не її слово: далі воно не їде як
        # її нагода (доти на другому ході ставало «розмовою»), `_типова_нагода` поставить знову
        # ТИПОВЕ-1: так само типове місце плитки (`типове_форми`) — його несе паспорт досі, але
        # сказала його не вона; перенесене звідси, воно ставало б словом моделі
        типова = ((ім == "нагода" and джерела_досі.get("нагода") == _ПН.ТИПОВА_НАГОДА_РЕЧІ)
                  or джерела_досі.get(ім) == _ПН.ТИПОВЕ_ПОЛЕ_ФОРМИ)
        об[ім] = к if к is not None else (досі.get(ім) if є(досі.get(ім)) and not типова else None)
    об["подія"] = _текст(в.get("event")) or _текст(досі.get("подія"))
