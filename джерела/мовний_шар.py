def прийняти_розмову(відповідь):
    """Відповідь моделі розмови → dict(внутрішня, частини, незнайомі, невідомо, заглушки, причина).

    `внутрішня` — оновлення паспорта, розібране ТИМ САМИМ шляхом, що переклад сценарію
    (`прийняти_вхід("scenario", …)`: пари → поле й уривок у `quotes`, коди поза переліком — у
    `незнайомі`). `need` стає й старою темою питання (`question_about`: look / app) — її читають
    гілки оцінки й довідки показу. `частини` — сирі частини відповіді; судить їх шов (`суд_частин`).
    Не JSON чи без `text` — причина, і хід іде шляхом main (як відмова перекладача доти)."""
    об, чому_не = _обʼєкт(відповідь)
    if not isinstance(об, dict):
        return dict(внутрішня={}, частини={}, незнайомі=[], невідомо=[], заглушки=[],
                    причина="not_json_object: %s" % (чому_не or type(об).__name__))
    оновлення = об.get("update") if isinstance(об.get("update"), dict) else {}
    р = прийняти_вхід("scenario", _json_.dumps(оновлення, ensure_ascii=False))
    незнайомі = list(р["незнайомі"]) + ["%s" % к for к in об if к not in _ЧАСТИНИ + ("update",)]
    частини = {}
    need = _код(об.get("need"))
    if need in _ВМ.ПОТРЕБИ:
        частини["need"] = need
    elif not _порожнє(need):
        незнайомі.append("need=%s" % need)
    for к in ("text", "invite", "ask"):
        т = об.get(к)
        if isinstance(т, str) and not _порожнє(т) and not _ВМ.невідомо(т):
            частини[к] = " ".join(т.split())
    теми = [_код(т) for т in (об.get("invite_topics") or []) if isinstance(т, str)] \
        if isinstance(об.get("invite_topics"), list) else []
    частини["invite_topics"] = [т for т in dict.fromkeys(теми) if т]
    ask_code = _код(об.get("ask_code"))
    if ask_code and not _порожнє(ask_code):
        частини["ask_code"] = ask_code
    в = р["внутрішня"]
    if частини.get("need") in ("app", "look"):
        в["question_about"] = частини["need"]
    причина = None if частини.get("text") or частини.get("ask") else "no_text_field"
    текст, зняте = _без_питань(частини.get("text"))
    return dict(внутрішня=в, частини=частини, незнайомі=незнайомі, невідомо=р["невідомо"],
                заглушки=_заглушки(об), причина=причина, текст=текст,
                відкинуто=[dict(частина="text", чому="question_in_text", зняте=зняте)] if зняте else [])


# ── СУД ЧАСТИН ВІДПОВІДІ (п.9 — ЗАБЕЗПЕЧУЄ КОД) ───────────────────────────────────────
# Речення рахуються за знаками кінця речення — розділові знаки, не слова (п.12): код не читає,
# ЩО вона чи модель сказали, лише ФОРМУ — чи це питання і скільки речень.
_РЕЧЕННЯ = re.compile(r"(?<=[.!?…])\s+")
_ПИТАННЯ = re.compile(r"[?？]")


def _без_питань(текст):
    """(текст без речень із «?», зняті речення) — форма, не слова: питати її може лише код."""
    речення = [р for р in _РЕЧЕННЯ.split(текст or "") if р.strip()]
    return " ".join(р for р in речення if not _ПИТАННЯ.search(р)), [р for р in речення if _ПИТАННЯ.search(р)]


def суд_частин(частини, дозволені, обовʼязкове):
    """Частини відповіді моделі → (текст бульбашки, теми запрошення, відкинуто, бракує_обовʼязкового).

    `дозволені` — теми поради, які код дозволяє на стані ПІСЛЯ ходу (`теми_дозволені`);
    `обовʼязкове` — обовʼязкові коди на тому самому стані. Відкинуте не губиться мовчки: кожен
    рядок `відкинуто` — {частина, чому} кодами, і він їде в запис виклику (звіт власника)."""
    import паспорт_нагоди as _ПН
    ч = частини or {}
    відкинуто = []
    текст, зняте = _без_питань(ч.get("text"))
    if зняте:
        відкинуто.append(dict(частина="text", чому="question_in_text", зняте=зняте))
    шматки = [текст] if текст else []
    ask = ч.get("ask")
    if ask:
        if ч.get("ask_code") not in обовʼязкове:
            відкинуто.append(dict(частина="ask", чому="not_required_after_turn", код=ч.get("ask_code")))
        else:
            шматки.append(ask)
    бракує = [к for к in обовʼязкове if not (ask and ч.get("ask_code") == к)]
    теми, invite = list(ч.get("invite_topics") or []), ч.get("invite")
    if invite or теми:
        чому = ("required_this_turn" if обовʼязкове else "no_topics" if not теми
                else "no_invite_text" if not invite
                else "too_many_topics" if len(теми) > _ПН.ПОРАД_ЗА_ХІД_МАКС
                else "topic_not_allowed" if any(т not in дозволені for т in теми)
                else "question_in_invite" if _ПИТАННЯ.search(invite)
                else "too_many_sentences" if len([р for р in _РЕЧЕННЯ.split(invite) if р.strip()]) > _ПН.ПОРАДА_РЕЧЕНЬ_МАКС
                else None)
        if чому:
            відкинуто.append(dict(частина="invite", чому=чому, теми=теми,
                                  дозволені=list(дозволені)))
            теми = []
        else:
            шматки.append(invite)
    return " ".join(шматки).strip(), теми, відкинуто, бракує


