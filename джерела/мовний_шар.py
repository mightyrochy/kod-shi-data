def _код(v):
    """Код у формі переліку: без пробілів по краях, нижній регістр, пробіл → «_»."""
    return re.sub(r"[\s-]+", "_", str(v).strip().lower()) if isinstance(v, str) else v


def _норм(с, v, шлях, незнайомі):
    """Значення за описом поля схеми → внутрішня мова або None (unknown / нема).

    ФОРМА НЕ ВБИВАЄ ЗМІСТ (Т-13): рядок там, де схема чекає список, стає списком з одного;
    рядок там, де чекає вільний текст, — текстом її мови. Код поза переліком не
    підставляється сусіднім — стає None, і шлях до нього йде в `незнайомі` (звіт власника).
    «Невідомо» в будь-якій формі (null, "null", "None", "невідомо") — None, а не її текст
    чи незнайомий код (`внутрішня_мова.невідомо`)."""
    if _ВМ.невідомо(v, с.get("enum") or ()):
        return None
    if _ref(с) == "free_text":
        if isinstance(v, dict) and str(v.get("free_text") or "").strip():
            return {"free_text": str(v["free_text"]).strip(), "lang": str(v.get("lang") or "uk")}
        return {"free_text": v.strip(), "lang": "uk"} if isinstance(v, str) else None
    if _ref(с) in _ОБʼЄКТИ:
        було = len(незнайомі)
        н = _норм({"type": "object", "properties": _ОБʼЄКТИ[_ref(с)][1]}, v, шлях, незнайомі)
        # РІЧ НЕ СТАЄ ІНШОЮ РІЧЧЮ (вимір MamayLM-12B 25.09, рядок 156: «не темного кольору» →
        # {slot: top, color_name: dark}; `dark` — не назва кольору, і без неї межа ставала
        # «жодного верху»). Ознаки речі — одне ціле: не прочиталась одна — річ не береться, у
        # `незнайомі` названо і ознаку, і річ. «Невідомо» в ознаці — не збій: її просто нема.
        # Її власна річ (`own_item`) тримається назвою — там губиться лише нечитана ознака.
        if _ref(с) == "thing" and н is not None and len(незнайомі) > було:
            незнайомі.append("%s — річ не взято: ознака не прочиталась" % шлях)
            return None
        # сама цитата без жодної ознаки — не річ: межі чи бажання в ній нема
        return None if isinstance(н, dict) and set(н) <= {"quote"} else н
    if с.get("type") == "object" and isinstance(с.get("additionalProperties"), dict):
        # ЦИТАТИ ПОЛІВ (`quotes`): {поле: уривок}; поле поза схемою сценарію — у `незнайомі`
        if not isinstance(v, dict):
            незнайомі.append("%s=%s" % (шлях, v))
            return None
        вих = {}
        for к, x in v.items():
            if к not in _ВМ.СЦЕНАРІЙ:
                незнайомі.append("%s.%s" % (шлях, к))
            elif isinstance(x, str) and not _ВМ.невідомо(x):
                вих[к] = x.strip()
        return вих or None
    if "enum" in с:
        if _код(v) in с["enum"]:
            return _код(v)
        незнайомі.append("%s=%s" % (шлях, v))
        return None
    if с.get("type") == "array":
        сп = v if isinstance(v, list) else [v]
        вих = []
        for і, x in enumerate(сп):
            н = _норм(с.get("items") or {}, x, "%s[%d]" % (шлях, і), незнайомі)
            if н is not None and н not in вих:
                вих.append(н)
        return вих[:с["maxItems"]] if с.get("maxItems") else вих
    if с.get("type") == "object" and с.get("properties"):
        if isinstance(v, list) and len(v) == 2 and set(с["properties"]) == {"from", "to"}:
            v = {"from": v[0], "to": v[1]}
        if not isinstance(v, dict):
            незнайомі.append("%s=%s" % (шлях, v))
            return None
        вих = {}
        for к, x in v.items():
            if к not in с["properties"]:
                незнайомі.append("%s.%s" % (шлях, к))
                continue
            н = _норм(с["properties"][к], x, "%s.%s" % (шлях, к), незнайомі)
            if н not in (None, []):
                вих[к] = н
        бракує = [к for к in (с.get("required") or []) if к not in вих]
        return None if (not вих or бракує) else вих
    if с.get("type") in ("number", "integer"):
        т = str(v).replace(",", ".").replace("−", "-").strip().rstrip("CcСс").replace("°", "").strip()
        if с["type"] == "integer" and ":" in т:      # година «18:00» — та сама година 18
            т = т.split(":")[0]
        try:
            ч = float(т)
        except ValueError:
            незнайомі.append("%s=%s" % (шлях, v))
            return None
        if (с.get("minimum") is not None and ч < с["minimum"]) or (с.get("maximum") is not None and ч > с["maximum"]):
            незнайомі.append("%s=%s" % (шлях, v))
            return None
        return int(round(ч)) if с["type"] == "integer" else ч
    if с.get("type") == "string":
        т = str(v).strip()
        if с.get("pattern") and not re.match(с["pattern"], т):
            незнайомі.append("%s=%s" % (шлях, v))
            return None
        return т
    if "oneOf" in с:
        for в in с["oneOf"]:
            if в.get("const") == U:
                continue
            зайве = []
            н = _норм(в, v, шлях, зайве)
            if н is not None:
                return н
        незнайомі.append("%s=%s" % (шлях, v))
        return None
    return None


def прийняти_вхід(вид, відповідь, ід_речей=None):
    """Відповідь вхідного перекладача → dict(внутрішня, незнайомі, невідомо, причина).

    `внутрішня` — лише поля з опорою (unknown і порожнє не пишуться): так код і звіт
    бачать рівно те, що перекладач почув. Не JSON — порожня внутрішня мова з причиною:
    жінка лишається зі своїм сценарієм, а не з вигаданим. `ід_речей` — речі образу для
    коментаря: річ з id поза ними не вигадується, а стоїть у `незнайомі`."""
    об, чому_не = _обʼєкт(відповідь)
    if not isinstance(об, dict):
        return dict(внутрішня={}, незнайомі=[], невідомо=[],
                    причина="відповідь не JSON-об'єкт (%s)" % (чому_не or type(об).__name__))
    поля, незнайомі, невідомо = ВИДИ_ВХОДУ[вид]["поля"], [], []
    внутрішня = {}
    for к, v in об.items():
        if к not in поля:
            незнайомі.append(к)
            continue
        було = len(незнайомі)
        н = _норм(поля[к], v, к, незнайомі)
        if н not in (None, [], {}):
            внутрішня[к] = н
        elif len(незнайомі) == було:   # перекладач сам сказав «unknown» (чи порожньо) — у звіт
            невідомо.append(к)
    if ід_речей is not None and внутрішня.get("about_items"):
        незнайомі += ["about_items.id=%s" % р["id"] for р in внутрішня["about_items"] if р["id"] not in ід_речей]
        внутрішня["about_items"] = [р for р in внутрішня["about_items"] if р["id"] in ід_речей]
        if not внутрішня["about_items"]:
            del внутрішня["about_items"]
    return dict(внутрішня=внутрішня, незнайомі=незнайомі, невідомо=невідомо, причина=None)


