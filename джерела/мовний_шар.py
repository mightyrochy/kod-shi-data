def _межі(речі):
    """Межі-речі → (списки вето ядра, {слово кольору: слоти}) — тими ж ключами, що читає ядро."""
    в, слоти = dict(типи=[], тканини=[], принти=[], кольори=[], зони=[]), {}
    додати = lambda к, w: w and w not in в[к] and в[к].append(w)
    for р in речі or []:
        колір = _ВМ.ключ("color_name", р.get("color_name")) or _ВМ.ключ("color_class", р.get("color_class"))
        тип = _ВМ.ключ("item_type", р.get("item_type"))
        додати("кольори", колір)
        if колір and р.get("slot"):
            слоти[колір] = _слоти_ядра(р["slot"])
        додати("типи", тип)
        if not тип and not колір and р.get("slot"):
            додати("типи", _ВМ.ключ("slot", р["slot"]))     # межа на весь слот («без сукні»)
        додати("тканини", _ВМ.ключ("fabric", р.get("fabric")))
        додати("принти", _ВМ.ключ("pattern", р.get("pattern")))
        додати("зони", _ВМ.ключ("zone", р.get("zone")))
        додати("типи", _ВМ.ключ("feature", р.get("feature")))
    return в, слоти


