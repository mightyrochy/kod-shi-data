# НЕДІЙСНИЙ ЕКРАН У РЯДКУ JSON (П-3; Н-1, 26.09, MamayLM, картка руки 3): модель написала
# «\н» — кириличну «н» на місці «n» екрана переводу рядка, — і вся відповідь не розбиралась:
# п'ять перекладених текстів картки лишились внутрішньою мовою. «\н» — це «\n»; перед
# іншим знаком, який не є екраном JSON, зворотна риска знімається. Пари «\\» регулярка
# бере цілими, тож буквальна риска перед «н» лишається рискою.
_ЕКРАН = re.compile(r"\\(.)", re.S)


def _екрани(т):
    """Текст відповіді з недійсними екранами JSON, полагодженими так, як сказано вище."""
    return _ЕКРАН.sub(lambda м: "\\n" if м.group(1) == "н"
                      else м.group(0) if м.group(1) in '"\\/bfnrtu' else м.group(1), т)


def _обʼєкт(відповідь, нотатки=None):
    """(JSON-об'єкт або масив із відповіді моделі, причина, коли не вийшло).

    Недійсний екран лагодиться (`_екрани`), лише коли суворий розбір не вдався; що так
    прочитано, дописується в `нотатки`, коли їх дали, — у запис виклику шару, не мовчки."""
    сир = str(відповідь or "").replace(_ВСТАВКА, " ")      # «▁» Lapa — пробіл (М-2)
    if нотатки is None:
        об, чому_не, _ = _ПР.розбір_останній(сир, ())
    else:
        об, чому_не = _ПР.розбір(сир)
    if об is None and _екрани(сир) != сир:
        об, _ = _ПР.розбір(_екрани(сир))
        if об is not None:
            сир = _екрани(сир)
            if нотатки is not None:
                нотатки.append("invalid_escape_read")
    if об is None:                  # `протокол.розбір` бере лише об'єкт; масив дочитується тут
        for т in dict.fromkeys((сир, _екрани(сир))):
            try:
                об = _json_.loads(re.sub(r"^```(?:json)?\s*|\s*```$", "", т.strip()))
                break
            except ValueError:
                об = None
    if нотатки is not None and (об is None or (isinstance(об, dict) and "```" in сир)):
        # лише там, де прочитане названо в записі; з огорожами суворий розбір бере ПЕРШУ версію
        for т in dict.fromkeys((сир, _екрани(сир))):
            злите, скільки = _обʼєкти_злито(т)
            if злите is not None and (об is None or скільки > 1):
                об = злите
                нотатки.append(КІЛЬКА_ОБʼЄКТІВ)
                break
    return об, чому_не


