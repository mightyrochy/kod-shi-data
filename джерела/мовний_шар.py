def _тип_en(с):
    """`_тип` англійською: яке значення чекає поле (коди, число, рядок її мовою, об'єкт, список)."""
    if "enum" in с:
        return "codes: " + ", ".join(к for к in с["enum"] if к != U)
    if _ref(с) == "free_text":
        return "a string in her language"
    if с.get("type") == "array":
        return "list" + (" (up to %d)" % с["maxItems"] if с.get("maxItems") else "") + " of " \
            + _тип_en(с.get("items") or {})
    if с.get("type") == "object" and с.get("properties"):
        return "{" + "; ".join("%s — %s" % (к, _тип_en(v)) for к, v in с["properties"].items()) + "}"
    if с.get("type") in ("number", "integer"):
        межі = [x for x in (с.get("minimum"), с.get("maximum")) if x is not None]
        return ("integer" if с["type"] == "integer" else "number") + (" %s–%s" % tuple(межі) if len(межі) == 2 else "")
    if с.get("type") == "string":
        return "string" + (" #rrggbb" if "#" in str(с.get("pattern") or "") else "")
    if "oneOf" in с:
        return " or ".join(_тип_en(в) for в in с["oneOf"] if в.get("const") != U)
    return "value"


