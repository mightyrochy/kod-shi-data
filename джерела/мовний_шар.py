# ЩО ТЕПЕР. Коли суворий розбір не вдався, відповідь читається як послідовність JSON-об'єктів, що
# стоять з початку рядка; вони зливаються по порядку, і ключ пізнішого перекриває той самий ключ
# ранішого — останнє слово моделі про кожен текст: повне виправлення дає рівно другий об'єкт,
# часткове («лише 13») не губить решти першого. Що так прочитано, каже нотатка
# `several_json_merged` у записі шару, сира відповідь — поруч; тому так читають лише виклики з
# `нотатки` (тексти картки, повідомлення), не мовчки. Обидві версії в огорожах ```json — та сама
# форма, але там суворий розбір не падає, а мовчки бере ПЕРШУ (невиправлену): `_У_ДУЖКАХ` знаходить
# першу огорожу. Тому з огорожами і кількома об'єктами злиття діє й після вдалого суворого розбору.
КІЛЬКА_ОБʼЄКТІВ = "several_json_merged"
_ПОЧАТОК_ОБʼЄКТА = re.compile(r"(?m)^[ \t]*(?:```(?:json)?[ \t]*\n[ \t]*)?\{")


def _обʼєкти_злито(т):
    """(цілі JSON-об'єкти з початку рядка, злиті по порядку — пізніший ключ перекриває, або None;
    скільки їх)."""
    декодер, кінець, злите, скільки = _json_.JSONDecoder(), 0, None, 0
    for м in _ПОЧАТОК_ОБʼЄКТА.finditer(т):
        п = м.end() - 1
        if п < кінець:                      # вкладений у вже прочитаний об'єкт
            continue
        try:
            об, кінець = декодер.raw_decode(т, п)
        except ValueError:
            continue
        if isinstance(об, dict):
            злите, скільки = dict(злите or {}, **об), скільки + 1
    return злите, скільки


