# ── СТОРОЖ ШАРУ: ПОЛЕ ТРИМАЄ ЦИТАТА ПЕРЕКЛАДАЧА, А НЕ СЛОВНИК КОДУ (М-1, В-4) ──────
# Доти шов віддавав `паспорт_з_json` порожні слова, і гейти опори main (`сказано_про`,
# `місце_зі_слів`) на порожньому тексті мовчали = пропускали: `place=office_corporate,
# hour=7, temperature_c=30` без жодної опори ставали паспортом. Звіряли ж ці факти ті самі
# читачі її слів у коді (`_вигадки`: словники чисел, місць, реєстрів) — мова в коді, проти
# CLAUDE.md п.12. Тепер перекладач сам називає, на чому стоїть кожне поле (`quotes`, `quote`
# речі), а код звіряє лише одне — що цей уривок справді є в її словах ходу (механіка
# `цитата_тримає` з #311: підрядок, без словника). Поле без такої цитати в паспорт не йде,
# і це видно рядком формату #309 у `не_взято_кодом` і в записі виклику шару.
_БЕЗ_ЦИТАТИ = ("event", "mood", "question", "question_about", "rest", "quotes", "event_formality")
_РЕЧІ_З_ЦИТАТОЮ = ("wants", "vetoes", "retract", "own_items")


def _до_звірки(текст):
    """Текст для звірки цитати: нижній регістр, один апостроф, розділові знаки — пробілом."""
    т = str(текст or "").lower().replace("’", "'").replace("ʼ", "'").replace("`", "'")
    return " ".join(re.sub(r"[^\w']+", " ", т).split())


def цитата_тримає(цитата, слова):
    """Чи дослівний уривок `цитата` стоїть у її словах `слова` (регістр, лапки, розділові
    знаки й пробіли не важать). Порожня цитата чи без жодної літери й цифри — не тримає."""
    ц = _до_звірки(цитата)
    return bool(re.search(r"[^\W_]", ц)) and ц in _до_звірки(слова)


def вигадка_рядком(поле, сказала, цитата, зробив="не взяв у паспорт"):
    """Рядок звіту про поле перекладача без опори в її словах — формат #309
    («вигадка моделі · крок · поле · …»)."""
    return ("вигадка моделі · крок шар · поле %s · модель сказала: %s · цитата: %s · що зробив код: %s"
            % (поле, _json_.dumps(сказала, ensure_ascii=False),
               ("«%s» — у її словах нема" % цитата) if цитата else "нема", зробив))


def _тримається(в, слова):
    """Внутрішня мова ходу → (лише поля й речі, чия цитата стоїть у її словах; рядки звіту).

    Вільний текст (подія, настрій, питання, решта) — сам її слова й цитати не потребує; смуга
    події (`event_formality`) тримається подією. Без її слів ходу (паспорт кодом із порожньою
    дельтою) звіряти нема чого — і перекладу там нема."""
    if not isinstance(в, dict) or not в:
        return {}, []
    цитати, вих, рядки = dict(в.get("quotes") or {}), {}, []
    for к, v in в.items():
        if к in _РЕЧІ_З_ЦИТАТОЮ:
            лишити = []
            for і, р in enumerate(v or []):
                ц = р.get("quote") or ((р.get("name") or {}).get("free_text") if к == "own_items" else None) \
                    or цитати.get(к)
                if цитата_тримає(ц, слова):
                    лишити.append(р)
                else:
                    рядки.append(вигадка_рядком("%s[%d]" % (к, і), {x: y for x, y in р.items() if x != "quote"}, ц))
            if лишити:
                вих[к] = лишити
        elif к == "event_formality" and not в.get("event"):
            рядки.append(вигадка_рядком(к, v, None, "не взяв: події, якої це смуга, у перекладі нема"))
        elif к in _БЕЗ_ЦИТАТИ or цитата_тримає(цитати.get(к), слова):
            вих[к] = v
        else:
            рядки.append(вигадка_рядком(к, v, цитати.get(к)))
    return вих, рядки


def паспорт_з_шару(внутрішня, сценарій, вето_чипів=None, паспорт_досі=None, драп=None, фото=None,
                   речі_з_фото=None, слова_ходу=""):
    """Внутрішня мова одного ходу → паспорт ядра, теми поради й обов'язкове.

    ДЕЛЬТА, А НЕ ПОВНИЙ ПАСПОРТ: перекладач переказує лише цей хід. Чого він не почув —
    лишається з паспорта досі; списки (бажання, межі, реєстри) доливаються, а те, від
    чого вона відмовилась (`retract`), знімається.
    ОДИН ПАРСЕР: паспорт збирає `паспорт_нагоди.паспорт_з_json` — той самий, що для
    виклику 0, — але слова йому не йдуть: читачам її слів (словник заперечень, опора
    числа й місця, реєстр зі слів) нема чого читати, і вони мовчать; межі тримаються
    ті, що почув перекладач (`вето_тверде` з них, без гейта слів). Функціональним
    моделям її сирі слова не їдуть (`слова` паспорта порожнє): лише структура — і вона
    несе все речення: подію зі смугою, решту сказаного (`решта`), поля на цитатах.
    СТОРОЖ (М-1, В-4): поле без цитати в `слова_ходу` не береться (`_тримається`).
    `речі_з_фото` — опис речей із фото від моделі з зором (виклик 0 без її слів)."""
    import паспорт_нагоди as _ПН
    import сценарій as _СЦ
    в, вигадки = _тримається(внутрішня, слова_ходу)
    досі = паспорт_досі if isinstance(паспорт_досі, dict) else {}
    джерела_досі = досі.get("джерело_полів") if isinstance(досі.get("джерело_полів"), dict) else {}
    є = lambda x: x not in (None, "", "невідомо", [], {})
    об = {}
    for поле, ім in _ПРОСТІ:
        к = _ВМ.ключ(поле, в.get(поле))
        # «щоденне», яке код підставив під її річ з фото, — не її слово: далі воно не їде як
        # її нагода (доти на другому ході ставало «розмовою»), `_типова_нагода` поставить знову
        типова = ім == "нагода" and джерела_досі.get("нагода") == _ПН.ТИПОВА_НАГОДА_РЕЧІ
        об[ім] = к if к is not None else (досі.get(ім) if є(досі.get(ім)) and not типова else None)
    об["подія"] = ((в.get("event") or {}).get("free_text") or досі.get("подія") or "")
    для_числа = lambda ч, поле, код: ч if ч is not None else _ВМ.ключ(поле, код)
    об["година"] = для_числа(в.get("hour"), "part_of_day", в.get("part_of_day"))
    об["темп_c"] = для_числа(в.get("temperature_c"), "weather_feel", в.get("weather_feel"))
    об["тривалість_год"] = в.get("duration_h")
    об["ноги_вище_см"] = в.get("legs_above_cm")
    for ім in ("година", "темп_c", "тривалість_год", "ноги_вище_см"):
        if об[ім] is None and є(досі.get(ім)):
            об[ім] = досі[ім]
    # ── ПОДІЯ БЕЗ КОДУ НЕ ГИНЕ І СУДИТЬ (М-1, В-1/В-6) ───────────────────────────
    # «Для походу на концерт»: коду нагоди нема → `подія` жила лише рядком для моделей, а суд
    # її речей стояв проти «щоденне» [3, 4] і казав «Нагоди ти не назвала». Подія несе свою
    # смугу (`event_formality`), і вона стає смугою сценарію рівно тоді, коли жодне
    # визначальне поле (нагода, місце, дрес-код, її ошатність — зі слів чи з форми) смуги не
    # дає: слово жінки й плитка переважають оцінку перекладача. Смуга з події позначена
    # `джерело_полів.ошатність = «подія»` і наступним ходом не видає себе за її слова.
    смуга = lambda ф: [ф["from"], ф["to"]] if isinstance(ф, dict) and "from" in ф else None
    ош_її = смуга(в.get("formality")) or (досі.get("ошатність") if джерела_досі.get("ошатність") != "подія" else None)
    ош_події = смуга(в.get("event_formality")) if в.get("event") else досі.get("ошатність_події")
    визначальне = any(об.get(к) for к in ("нагода", "місце", "дрес_код")) or any(
        (сценарій or {}).get(к) not in (None, "") for к in _СЦ.ВИЗНАЧАЛЬНІ)
    з_події = bool(ош_події) and not ош_її and not визначальне
    об["ошатність"] = ош_її or (ош_події if з_події else None)
    мк = в.get("makeup") or {}
    об["макіяж"] = ({"рівень": _ВМ.ключ("makeup_level", мк.get("level")), "губи": мк.get("lips_hex")}
                    if мк else досі.get("макіяж"))
    знято_в, _ = _межі(в.get("retract"))
    знято_б = {_фраза(р) for р in в.get("retract") or []}
    нові_в, нові_слоти = _межі(в.get("vetoes"))
    вето_досі = досі.get("вето") if isinstance(досі.get("вето"), dict) else {}
    об["вето"] = {к: [w for w in list(вето_досі.get(к) or []) + нові_в[к]
                      if w not in знято_в[к]] for к in нові_в}
    об["вето"] = {к: list(dict.fromkeys(сп)) for к, сп in об["вето"].items()}
    об["бажання"] = list(dict.fromkeys([ф for ф in list(досі.get("бажання") or []) + [_фраза(р) for р in в.get("wants") or []]
                                        if ф and ф not in знято_б]))
    об["реєстр_людини"] = list(dict.fromkeys([_ВМ.ключ("register", р) for р in в.get("registers") or []]
                                             + list(досі.get("реєстр_людини") or [])))[:2]
    об["настрій"] = [т["free_text"] for т in в.get("mood") or []] or list(досі.get("настрій") or [])
    if речі_з_фото is not None:
        об["речі_з_фото"] = речі_з_фото
    об = {к: v for к, v in об.items() if v is not None}
