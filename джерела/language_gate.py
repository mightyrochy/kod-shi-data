def _знайти(текст, формули):
    т = str(текст or "")
    з = []
    for ф in формули:
        for m in re.finditer(ф, т, re.I | re.U):
            з.append(dict(де=(m.start(), m.end()), фрагмент=m.group(0), регекс=ф))
    return з


