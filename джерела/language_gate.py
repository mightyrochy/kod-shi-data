_РОС_ЛИШЕ_ЗІ_СВІДКОМ = {"образ", "носить", "сумка", "шарф", "браслет", "ресторан"}


def російське(текст):
    """Список підозрілих фрагментів російською; порожній — текст чистий."""
    т = str(текст or "")
    знайдені = []
    for м in _РОС_ЛІТЕРИ.finditer(т):
        слово = _re.search(r"[А-Яа-яІіЇїЄєҐґЫыЭэЪъЁё'ʼ-]+", т[max(0, м.start()-20):min(len(т), м.end()+20)])
        знайдені.append(dict(фрагмент=(слово.group(0) if слово else м.group(0)), чому="літера, якої нема в українській абетці"))
    for м in _РОС_ЗАКІНЧЕННЯ.finditer(т):
        знайдені.append(dict(фрагмент=м.group(0), чому="російське закінчення «-%s»" % м.group(1)))
    низ = т.lower()
    свідок = bool(знайдені)
    for сл in _РОС_СЛОВА:
        if сл in _РОС_ЛИШЕ_ЗІ_СВІДКОМ and not свідок:
            continue
        for м in _re.finditer(r"\b" + _re.escape(сл) + r"\b", низ):
            # у контексті ще двох слів — щоб модель бачила, ЩО переписати
            поч = низ.rfind(" ", 0, max(0, м.start()-1)); кін = низ.find(" ", м.end()+1)
            знайдені.append(dict(фрагмент=т[(поч+1 if поч >= 0 else 0):(кін if кін >= 0 else len(т))].strip(),
                                 чому="російське слово «%s»" % сл))
    # дедуплікація за фрагментом
    вих, бачено = [], set()
    for з in знайдені:
        к = з["фрагмент"].lower()
        if к not in бачено:
            бачено.add(к); вих.append(з)
    return вих


def перевірити(текст, режим="блокувати", цілі_людини=None):
    """Головний вхід. Повертає вердикт по одному фрагменту тексту.

    `режим`: "блокувати" — будь-яке анти-правило робить текст невидаваним;
             "мітити"    — лише позначає (для дебагу й для звіту по чужому тексту).
    `цілі_людини`: список зон тіла, які людина САМА назвала своєю ціллю. R-LNG-01
             [hard] знімається рівно для них. Дефолт — порожньо, і це не недогляд:
             ненадана goal-ініціація означає, що ініціації не було, а не що вона
             невідома. Строгий бік — правильний бік для правила сили `hard`.

    Повертає dict із `можна_видавати`, списками порушень, карантину й фольклорних
    чисел. `дозволено` кожного порушення несе формулювання, яким корпус велить
    його замінити — без цього шар вище винайшов би ту саму заборону іншими словами."""
    порушення, карантин, фольклор = [], [], []
    цілі = [str(z).lower() for z in (цілі_людини or [])]
    for а in АНТИ:
        if а.get("умовне") == "ярлик":
            continue                       # R-TYP-05 має власну гілку нижче
        з = _знайти(текст, а["формули"])
        if з and а["id"] == "R-LNG-01" and цілі:
            # Зона, яку людина сама внесла в цілі, виходить з-під правила — і лише
            # вона. Знімається спрацювання, не правило: решта зон далі під гейтом.
            з = [x for x in з if not any(ц[:4] in x["фрагмент"].lower() for ц in цілі)]
        if з:
            порушення.append(dict(правило=а["id"], суть=а["суть"], сила="hard",
                                  збіги=[x["фрагмент"] for x in з],
                                  дозволено_натомість=а["дозволено"],
                                  позиції=[x["де"] for x in з]))
    # ── R-TYP-05: ЯРЛИК БЕЗ ПЕРЕКЛАДУ В ОСІ ───────────────────────────────────
    # Умовне правило, тому окремою гілкою: сам ярлик не заборонений (корпус зве
    # його очікуваною мовою UA-ринку), заборонена його роль МЕХАНІЗМУ. Різницю
    # робить присутність осьового слова в тому самому фрагменті.
    _ярл = _знайти(текст, ЯРЛИКИ_ТИПОЛОГІЙ)
    if _ярл:
        _осі = _знайти(текст, ОСІ_ПЕРЕКЛАДУ)
        if not _осі:
            _п = [а for а in АНТИ if а["id"] == "R-TYP-05"][0]
            порушення.append(dict(правило="R-TYP-05", суть=_п["суть"], сила="hard",
                                  збіги=[x["фрагмент"] for x in _ярл],
                                  дозволено_натомість=_п["дозволено"],
                                  позиції=[x["де"] for x in _ярл],
                                  чому="ярлик названо, осей не названо — отже ярлик "
                                       "виступає механізмом, а не містком"))
    for к in КАРАНТИН:
        з = _знайти(текст, к["формули"])
        if з:
            карантин.append(dict(правило=к["id"], суть=к["суть"], сила="hint",
                                 збіги=[x["фрагмент"] for x in з], чому=к["чому"]))
    for ф, назва in ФОЛЬКЛОРНІ_ЧИСЛА:
        з = _знайти(текст, [ф])
        if з:
            фольклор.append(dict(константа=назва, збіги=[x["фрагмент"] for x in з],
                                 чому="фольклорна константа — форма/скіс так, ЧИСЛО ні. "
                                      "У тексті людині вона звучить як вимір"))
    # РОСІЙСЬКА — ПОРУШЕННЯ ТОГО САМОГО КЛАСУ, ЩО Й АНТИ-ПРАВИЛА: текст не
    # видається жінці, поки модель не перепише його українською.
    _рос = російське(текст)
    if _рос:
        порушення.append(dict(правило="R-LNG-UA", сила="hard",
                              суть="російська мова в тексті для жінки: " + "; ".join("«%s»" % з["фрагмент"] for з in _рос[:4]),
                              збіги=[з["фрагмент"] for з in _рос],
                              дозволено_натомість="той самий зміст українською, без жодного російського слова чи закінчення",
                              позиції=[]))
    можна = not (порушення and режим == "блокувати")
    ліцензовані = []
    for д in ДОЗВОЛЕНІ:
        з = _знайти(текст, д["формули"])
        if з:
            ліцензовані.append(dict(правило=д["id"], суть=д["суть"],
                                    збіги=[x["фрагмент"] for x in з], чому=д["чому"]))
    return dict(
        можна_видавати=можна, режим=режим,
        порушень=len(порушення), порушення=порушення,
        карантин=карантин, фольклорні_числа=фольклор,
        ліцензовані=ліцензовані,
        чому=("текст чистий за списком анти-правил" if not порушення else
              "заборонені формули: %s" % ", ".join(п["правило"] for п in порушення)),
        межа="гейт ловить ФОРМУЛЮВАННЯ, не НАМІР. Перефразування обходить його "
             "тривіально; «візуально врівноважить пропорції» пройде, хоч це те саме "
             "«виправити тіло». Це фільтр останньої милі, не гарантія")


def перевірити_знахідки(знахідки, режим="блокувати", цілі_людини=None):
    """Прогін по полях знахідок, які реально їдуть людині: суть, чому, ремонт.

    НАВІЩО ОКРЕМА ФУНКЦІЯ: заборонена формула найімовірніше з'явиться не у вільному
    тексті ШІ, а в РЕМОНТІ наших власних правил — саме там система радить, що робити
    з тілом. Тому власний вихід перевіряється тим самим гейтом, що й чужий."""
    брудні, _ліц = [], set()
    for z in (знахідки or []):
        шматки = [z.get("суть"), z.get("чому")]
        р = z.get("ремонт")
        шматки += (list(р) if isinstance(р, (list, tuple)) else [р])
        текст = " ".join(str(x) for x in шматки if x)
        в = перевірити(текст, режим=режим, цілі_людини=цілі_людини)
        _ліц |= {x["правило"] for x in (в.get("ліцензовані") or [])}
        if в["порушення"] or в["карантин"] or в["фольклорні_числа"]:
            брудні.append(dict(правило=z.get("правило"), вердикт=в))
    # ── АНТИ-ПРАВИЛО, ЯКЕ ПРОМОВЧАЛО, ТЕЖ СПРАЦЮВАЛО ────────────────────────
    # ЩО ЦЕ МІНЯЄ (правило 3). before: гейт досяжності звітував 12 правил цього
    # модуля (R-ABC-08/11/13, R-LNG-01, R-NVB-02, R-PP-09, R-PSY-01/02/03/06,
    # R-TYP-04/05, K-PC-06) як МЕРТВІ. Вони не мертві — вони анти-правила, і на
    # чистому тексті мовчать за призначенням. Але «промовчало правильно» і
    # «ніколи не викликалось» лишали В ЛОЗІ рівно однаковий слід: порожнечу.
    # Тому за списком мертвих не можна було діяти: лікувати треба різне.
    # after: у слід іде ФАКТ ПЕРЕВІРКИ з результатом. Правило, яке перевірили і
    # яке не спрацювало, — виконане правило; правило, якого не перевіряли,
    # тепер видно окремо.
    # МЕЖА: слід каже, що перевірка ВІДБУЛАСЬ, і не каже, що патерн ловить усі
    # формулювання. Повнота патернів міряється кейсами внизу файлу, не цим.
    try:
        import trace as _СЛ
        _спрац = {д.get("вердикт", {}).get("правило") for д in брудні}
        # ID буває складеним («R-PP-09/R-LOC-06»): одне анти-правило покриває
        # два коди корпусу. Пишемо кожен окремо, інакше лог не звʼяже жодного.
        for _а in АНТИ:
          for _ід in str(_а["id"]).split("/"):
            if not _ід.strip() or "-" not in _ід:
                continue
            _СЛ.запис(_ід.strip(), "мовний гейт", "мовний_гейт",
                      значення=("СПРАЦЮВАЛО" if _а["id"] in _спрац else
                                "перевірено на %d знахідках, чисто" % len(знахідки or "")),
                      напрям=("порушення" if _а["id"] in _спрац else "мовчить за призначенням"))
        # ── КАРАНТИН, ФОЛЬКЛОРНІ ЧИСЛА Й БІЛИЙ СПИСОК ТЕЖ ЛИШАЮТЬ СЛІД ────────
        # ЗНАЙДЕНО ГЕЙТОМ ДОСЯЖНОСТІ, І ЗНАЙДЕНО ПРАВИЛЬНО. R-ABC-11 (Φ як поріг),
        # R-ABC-13 (WHR=0.7), R-PSY-03 (маркетинг «рятуємо від вибору»), R-PRN-09,
        # R-USE-02, R-WRD-01, K-CLR-04 РЕАЛІЗОВАНІ тут патернами й справді
        # перевіряються на кожному прогоні. Але слід писався лише за списком
        # `АНТИ`, тож у лозі вони виглядали так само, як невикликані. Тобто дефект
        # був не в правилах, а в тому, що дві з трьох застав цього файлу були
        # невидимі для логу. Тепер видимі всі три плюс білий список.
        _к_спрац = set()
        _ф_спрац = set()
        _л_спрац = set(_ліц)
        for д in брудні:
            в = д.get("вердикт", {})
            _к_спрац |= {x["правило"] for x in (в.get("карантин") or [])}
            _ф_спрац |= {x["константа"] for x in (в.get("фольклорні_числа") or [])}
        _пари = ([(str(к["id"]), "карантин", к["id"] in _к_спрац) for к in КАРАНТИН]
                 + [(назва, "фольклорна константа як поріг",
                     назва in _ф_спрац) for _, назва in ФОЛЬКЛОРНІ_ЧИСЛА]
                 + [(str(д["id"]), "білий список", д["id"] in _л_спрац)
                    for д in ДОЗВОЛЕНІ])
        for _сир, _ярлик, _було in _пари:
            for _ід in re.findall(r"[KR]-[A-ZА-Я0-9]{2,5}-\d{2}", _сир):
                _СЛ.запис(_ід, _ярлик, "мовний_гейт",
                          значення=("СПРАЦЮВАЛО" if _було else
                                    "перевірено на %d знахідках, чисто"
                                    % len(знахідки or "")),
                          напрям=("знайдено" if _було else "мовчить за призначенням"))
    except Exception:
        pass
    return dict(усього=len(знахідки or []), брудних=len(брудні), деталі=брудні,
                перевірено_анти=len(АНТИ), чисто=(not брудні))


