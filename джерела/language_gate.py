# R-LNG-01 знімається goal-ініціацією — і рівно для названої зони. Окремий список,
# бо ці кейси потребують ДРУГОГО аргументу, а не лише тексту.
_КЕЙСИ_ЦІЛІ = [
 ("Ця спідниця акцентує стегна", ["стегна"], True,
  "людина сама внесла стегна в цілі — правило знімається"),
 ("Ця спідниця акцентує стегна", ["плечі"], False,
  "у цілях інша зона — правило лишається"),
 ("Ця спідниця акцентує стегна", [], False,
  "цілей нема: ненадана goal-ініціація = ініціації не було"),
]


def прогін():
    впало = 0
    print("=" * 78)
    print("МОВНИЙ ГЕЙТ: 12 анти-правил корпусу, які досі не мали коду")
    print("=" * 78)
    print("\n%-62s %s" % ("текст", "вердикт"))
    print("-" * 78)
    for текст, очік_чисто, очік_правило in _КЕЙСИ:
        в = перевірити(текст)
        чисто = not в["порушення"]
        ок = (чисто == очік_чисто)
        якщо = "" if чисто else в["порушення"][0]["правило"]
        if not ок or (очік_правило and якщо != очік_правило):
            ок = False
        впало += (not ок)
        print("%s %-60s %s" % ("  ✓" if ок else "  ✗", текст[:60],
                               ("чисто" if чисто else якщо)))
    # ── ЦІЛІ ЛЮДИНИ: R-LNG-01 знімається рівно для названої зони ──────────────
    print("\n" + "-" * 78)
    print("R-LNG-01 · goal-ініціація: та сама фраза, різні цілі людини")
    for текст, цілі, очік_чисто, чому in _КЕЙСИ_ЦІЛІ:
        в = перевірити(текст, цілі_людини=цілі)
        чисто = not в["порушення"]
        ок = (чисто == очік_чисто)
        впало += (not ок)
        print("  %s цілі=%-12s %s" % ("✓" if ок else "✗",
                                      str(цілі), чому))
    # ── БІЛИЙ СПИСОК: ліцензована формула мусить бути ВПІЗНАНА, не лише пропущена
    print("\n" + "-" * 78)
    print("БІЛИЙ СПИСОК · ліцензовані формули (R-PSY-06 та ін.)")
    for д in ДОЗВОЛЕНІ:
        зразок = {"R-PSY-06": "На вас звертають увагу значно менше, ніж здається",
                  "R-PSY-01": "Читається як зібраний образ під ділову зустріч",
                  "R-TYP-05": "Якщо ви звикли до кольоротипів — це приблизно "
                              "висока глибина і холодна температура"}[д["id"]]
        в = перевірити(зразок)
        впізнано = any(x["правило"] == д["id"] for x in в["ліцензовані"])
        ок = впізнано and в["можна_видавати"]
        впало += (not ок)
        print("  %s %-10s %s" % ("✓" if ок else "✗", д["id"], зразок[:56]))

    # ── ФОЛЬКЛОРНІ КОНСТАНТИ: «не заблоковано» ще не означає «впізнано» ────────
    # Кейс вище перевіряє лише, що текст не блокується. Але сенс R-ABC-11/13 не в
    # тому, щоб пропустити, а в тому, щоб ПОЗНАЧИТИ: число звучить людині як вимір,
    # хоч виміром не є. Без цієї перевірки правило зараховувалось би за мовчання.
    print("\n" + "-" * 78)
    print("ФОЛЬКЛОРНІ КОНСТАНТИ · мусять бути позначені, не заблоковані")
    for текст, очік in (("Поділ ставимо за золотим перетином 1.618", "R-ABC-11"),
                        ("Ціль — WHR 0.7, це ідеал", "R-ABC-13"),
                        ("Капсула на 33 речі — базовий підхід", "R-WRD-01"),
                        ("82% речей носять менше 3 разів на рік", "R-USE-02")):
        в = перевірити(текст)
        позначки = " ".join(x["константа"] for x in в["фольклорні_числа"])
        ок = (очік in позначки) and в["можна_видавати"]
        впало += (not ок)
        print("  %s %-10s %-44s → %s" % ("✓" if ок else "✗", очік, текст[:44],
                                         позначки[:30] or "НЕ ПОЗНАЧЕНО"))
    print("\n" + "-" * 78)
    print("КАРАНТИН · сила ≤ hint до перевірки, не заборона")
    for текст, очік in (("Рятуємо вас від перевантаження вибором", "R-PSY-03"),
                        ("Камуфляжний принт цього сезону", "R-PRN-09")):
        в = перевірити(текст)
        к = " ".join(x["правило"] for x in в["карантин"])
        ок = (очік in к) and в["можна_видавати"]
        впало += (not ок)
        print("  %s %-10s %-44s → %s" % ("✓" if ок else "✗", очік, текст[:44],
                                         к[:30] or "НЕ ПОЗНАЧЕНО"))

    # роздільна здатність: скільки ДОЗВОЛЕНОГО тексту гейт пропускає
    дозв = [c for c in _КЕЙСИ if c[1]]
    хибних = sum(1 for т, _, _ in дозв if перевірити(т)["порушення"])
    print("\n" + "-" * 78)
    print("  дозволених формулювань перевірено: %d, з них хибно затавровано: %d"
          % (len(дозв), хибних))
    print("  заборонених перевірено: %d, з них пропущено: %d"
          % (len(_КЕЙСИ) - len(дозв),
             sum(1 for т, ч, _ in _КЕЙСИ if not ч and not перевірити(т)["порушення"])))
    print("\n" + "=" * 78)
    print(("ГЕЙТ ПРАЦЮЄ" if not впало else "ПРОВАЛІВ: %d" % впало) +
          "  —  але він ловить ФОРМУЛИ, не НАМІР, і реального тексту системи ще нема,")
    print("тож роздільна здатність на живому виході НЕ ВИМІРЯНА.")
    print("=" * 78)
    return впало


if __name__ == "__main__":
    raise SystemExit(прогін())
