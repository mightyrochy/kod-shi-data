/* Підготовка шаблону показ.html для тестів — ЄДИНЕ місце, звідки
   тест_показу.js і наскрізь.js беруть список плейсхолдерів __...ПОКАЗУ__ і
   підставляють у нього тестові значення.

   ЩО ЦЕ ЛАГОДИТЬ (рядок 69 дошки). Список плейсхолдерів жив у двох файлах
   окремо: коли build_артефакт.py і тест_показу.js завели __ДОВІДНИК_ПОКАЗУ__
   (Т-08 крок 3), наскрізь.js про нього не дізнався. Непідставлений плейсхолдер
   лишався текстом у `const ДОВІДНИК = __ДОВІДНИК_ПОКАЗУ__;` — SyntaxError на
   старті сторінки, і батарея не міряла нічого. Список тепер один, і додавання
   нового плейсхолдера в build_артефакт.py без цього файла не мине компіляції:
   обидва тести читають той самий ПЛЕЙСХОЛДЕРИ_ПОКАЗУ. */
const ПЛЕЙСХОЛДЕРИ_ПОКАЗУ = ["__МОДУЛІ_ПОКАЗУ__", "__ЗБІРКА_ПОКАЗУ__", "__ВІДБИТОК__",
  "__ФІД_ПОКАЗУ__", "__КАТАЛОГ_ПОКАЗУ__", "__ДОВІДНИК_ПОКАЗУ__"];

/* Довідник нагод/місць/кодів — вивід `pipeline.довідник()`, як і в збірці.
   Без нього `сц-місце` (`<select>`) не має жодного `<option>`, і код, який
   виставляє його `.value` напряму, мовчки нічого не обирає. Без python поруч
   лишаються порожні таблиці — виклик, що це кличе, друкує факт сам. */
function прочитатиДовідникJSON(джерело) {
  try {
    return require("child_process").execSync(
      'python3 -c "import json, pipeline; print(json.dumps(pipeline.довідник(), ensure_ascii=False))"',
      {cwd: джерело, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"]}).trim().split("\n").pop();
  } catch (e) {
    console.log("  (довідник не зібрався з python — таблиці порожні: " + String(e).slice(0, 80) + ")");
    return '{"нагоди":[],"місця":[],"коди":[],"дефолт_діапазон":[3,6]}';
  }
}

/* Підставляє тестові значення в ШАБЛОН показ.html (не в зібраний продукт: для
   зібраного html — інший формат, регексом по оголошенню `const ФІД_П = "...";`
   — цю підстановку тест_показу.js веде сам). Кидає, якщо для якогось
   плейсхолдера зі списку значення не дали: краще впасти тут, ніж лишити
   непідставлений плейсхолдер у зібраній сторінці. */
function підставитиШаблон(html, значення) {
  let р = html;
  for (const пл of ПЛЕЙСХОЛДЕРИ_ПОКАЗУ) {
    if (!(пл in значення)) throw new Error("підставитиШаблон: нема значення для " + пл);
    р = р.split(пл).join(значення[пл]);
  }
  return р;
}

module.exports = { ПЛЕЙСХОЛДЕРИ_ПОКАЗУ, прочитатиДовідникJSON, підставитиШаблон };
