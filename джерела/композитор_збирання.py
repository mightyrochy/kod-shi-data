        # None — нагода не траурна; тоді пул той самий, що доти, байт у байт.
        траур_пулу=(dict(випадок=_траур_пулу, знято=_зняв_траур) if _траур_пулу else None),
        кандидатів={с: len(к) for с, к in по_слотах.items()},
