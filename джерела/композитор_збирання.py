                # відкинувши ті, що вже є ядром. Відколи `bridge` будує ядро
                # СОЮЗОМ усіх гілок (01.09.2026, «гілка is None»), відкидається
                # геть усе: на цій людині союз пʼятьох схем дає 251 вікно ядра і
