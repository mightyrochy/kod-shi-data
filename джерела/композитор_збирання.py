    # КОД ОБРАЗІВ НЕ ЗБИРАЄ. Він дає кандидатів у слоти; образи складає ші; код
    # СУДИТЬ складене (`pipeline.перевірити_від_моделі`). Власний образ коду не був
    # продуктом і не читався ніде поза самим кодом: ні шаблон артефакта, ні
    # `показ.html` не згадують `образ_коду` жодного разу (зміряно 30.08 і ще раз
    # 31.08). Єдиним його виходом був рядок «ВУЗЬКЕ МІСЦЕ образу, який зібрав код»
    # у промпті — 3 % тексту, порожній у 6 сценах із 8.
    #
    # ЩО ЦЕ ЗВІЛЬНЯЄ. (1) ≈12 с на прогін — 60 % часу збирання йшло на 200 перевірок
    # комбінацій, які нікуди не доїжджали. (2) Пам'ять: `list(itertools.product(...))`
    # росте як K^|слоти|. На чотирьох слотах 5⁴ = 625 кортежів; щойно система
    # почала просити всі слоти каталогу — 5¹⁶ ≈ 152 мільярди, і прогін убивало
