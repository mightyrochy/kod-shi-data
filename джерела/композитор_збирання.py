def зібрати(F, каталог, вікна=None, тіло=None, слоти=None,
            жорстке_ні=None, вето=None, самозвіт=None, **kw):
    """Головний вхід. Повертає образ + ЧОМУ саме він, + що відкинуто й чому.

    Жодного числа «якості образу» не повертає навмисно: R-ABC-08 забороняє числовий
    універсальний style-score, і сума сил знахідок нею б і стала, якби вийшла назовні
    як оцінка. Вона тут — КЛЮЧ СОРТУВАННЯ, і подається саме так."""
    слоти = tuple(слоти or СЛОТИ_БАЗОВІ)
    # ── K-IO-01: ПРОФІЛЬ І СЦЕНАРІЙ — ОБОВʼЯЗКОВІ ВХОДИ (19.09.2026) ──────────
    # Гейт стоїть тут, а не в `bridge.порада` (та навмисно працює до збирання й
    # без пулу) і не в `_поза_сценою` (там «без сцени — нічого не чіпає» — саме
    # це мовчання й закривається). Вихід — та сама форма, що в «порожні слоти»:
    # названий брак, не виняток і не образ під дефолтну смугу. Що таке «сценарію
    # нема» — `сценарій.ВИЗНАЧАЛЬНІ`. Прямі викликачі без нагоди (прилади) тепер
    # дістають `зібрано=False` і `бракує` — це їхній вхід, не дефолт композитора.
    import сценарій as _СЦ
    _брак = None
    if not F:
        _брак = ("профілю нема — образ не збирається: потрібні шкіра, волосся й очі", ["профіль"])
    elif not _СЦ.є_сценарій(kw):
        _брак = (_СЦ.БРАК_СЦЕНАРІЮ, list(_СЦ.ВИЗНАЧАЛЬНІ))
    if _брак:
        return dict(зібрано=False, чому=_брак[0], бракує=_брак[1], правило="K-IO-01",
                    що_робити="назвати нагоду, місце, дрес-код або ошатність — образ "
                              "збирається під подію, а не під невідомий дефолт",
                    відкинуто=[], ноти_слотів={}, слоти_випали=[],
                    кандидатів={с: 0 for с in слоти}, _кандидати={})
    # ── САМОЗВІТ ЇДЕ ВЛАСНИМ КЛЮЧЕМ ДО `_оцінити` (Н-V04-011) ────────────────
    # `kw` тут — поля СЦЕНАРІЮ, і самозвіт у них не приходив ніколи, тож
    # `palettes.осі` під K-PAL-16 судила бік людини утриманою віссю навіть тоді,
    # коли людина відповіла на картки. Кладеться в `kw` рівно тому, що всі три
    # шляхи до `_оцінити` (`_оцінити_комбінації`, `_вигляд_виміру`,
    # `_образи_для_виміру`) передають саме його; іменований параметр `_оцінити`
    # знімає ключ із `kw` і в `pipeline.перевірити_образ` він не потрапляє.
    if самозвіт: kw["самозвіт"] = самозвіт
    # ── ТЕМПЕРАТУРА САМА ПРОСИТЬ ВЕРХНІЙ ШАР ─────────────────────────────────
    # ЗАФІКСОВАНИЙ ДЕФЕКТ (check_edits §28): «K-WEA-01 діагностує брак шару
    # НЕПЕРЕРВНО (+12 → 0.5 · +2 → 0.75 · −10 → 1.0), а композитор НЕ МАЄ ЧИМ ЦЕ
    # ПОЛАГОДИТИ — правило лишає слід, але не міняє рішення». Слот тепер досяжний,
    # але доти його мусив попросити ВИКЛИКАЧ, тобто знати відповідь наперед.
    # Тут температурна мапа корпусу (та сама, що живить K-WEA-01) просить слот
    # САМА: якщо смуга хоче більше ніж один шар на торсі, верхній шар додається.
    # Він НЕОБОВʼЯЗКОВИЙ, тож при нулі SKU випаде з названою причиною — діагноз
    # K-WEA-01 лишиться, але тепер він означатиме «у каталозі нема», а не «ніхто
    # не спитав».
    # ВОРОТА ДВОБІЧНІ (31.08.2026). Доти мапа лише ДОДАВАЛА слот, бо в дефолтних
    # чотирьох його не було, і «зняти» не було чого. Відколи код просить усі слоти
    # каталогу, верхній шар стоїть завжди — і при +26 °C модель діставала пальто
    # в пул. Зміряно: на фіді стенда 13 згадок «верхній_шар» у промпті і в холод,
    # і в спеку. Тепер та сама мапа, що просить шар, його й знімає.
    _нота_шару = None
    _слоти_дефолтні = bool(kw.pop("слоти_дефолтні", False))
    _темп = kw.get("темп_c")
    if _темп is not None:
        import outfit as _O
        _смуга = next((d for lo, hi, d in _O.ТЕМП_МАПА if lo <= _темп < hi), None)
        _хоче = bool(_смуга and _смуга["шари"] > 1)
        if _хоче and "верхній_шар" not in слоти:
            слоти = слоти + ("верхній_шар",)
        # ЯВНИЙ ЗАПИТ ВИКЛИКАЧА СИЛЬНІШИЙ ЗА МАПУ. Перша версія двобічних воріт
        # знімала шар завжди — і зривала слот навіть тоді, коли його попросили
        # руками (CLI, тест «пальто в спеку примусово»). Мапа має право прибирати
        # лише те, що САМА ж і поставила за замовчуванням.
        # ШАР ТРИМАЮТЬ НЕ ЛИШЕ ГРАДУСИ (05.09.2026): дрес-код від 7 (жакет — частина коду),
        # опади/вітер, вулиця нижче +22 °C — верхній шар лишається в слотах; мапа знімає
        # його лише в теплі, у приміщенні, без погоди.
        _о = kw.get("_ошатність"); _lo = None
        if isinstance(_о, (list, tuple)) and len(_о) == 2:
            try: _lo = min(float(_о[0]), float(_о[1]))
            except (TypeError, ValueError): _lo = None
        _тримає = ((_lo is not None and _lo >= 7)
                   or (str(kw.get("дрес_код") or "").lower().replace(" ", "_").replace("-", "_") in ("business_formal", "cocktail", "black_tie", "smart", "formal", "формальний", "вечірній"))
                   or (kw.get("опади") not in (None, "", "ні", 0, False))
                   or ((kw.get("вітер") or 0) and float(kw.get("вітер") or 0) >= 6)
                   or (kw.get("_формат") in ("просто неба", "змішано") and float(_темп) < 22))
        if not _хоче and "верхній_шар" in слоти and _слоти_дефолтні and _тримає:
            _нота_шару = ("верхній шар ЛИШЕНО попри %s °C: %s" % (_темп,
                          "дрес-код" if ((_lo is not None and _lo >= 7) or str(kw.get("дрес_код") or "").lower().replace(" ", "_").replace("-", "_") in ("business_formal", "cocktail", "black_tie", "smart", "formal", "формальний", "вечірній")) else "погода/вулиця"))
        elif not _хоче and "верхній_шар" in слоти and _слоти_дефолтні:
            слоти = tuple(с for с in слоти if с != "верхній_шар")
            _нота_шару = ("слот ЗНЯТО температурою: смуга %s °C просить один шар на торсі, "
                          "тож верхній шар тут зайвий — це не брак каталогу" % _темп)
    # ── НЕОБОВʼЯЗКОВІ СЛОТИ: ПОРОЖНЬО МАЄ ДЕГРАДУВАТИ, А НЕ ВБИВАТИ ЗБІРКУ ────
    # ЗАФІКСОВАНИЙ ДЕФЕКТ (check_edits §28, 26.08.2026): варто було подати
    # «верхній_шар» у слотах — і збірка поверталася `зібрано=False` при 0 SKU,
    # тобто образу не було ВЗАГАЛІ. На обох живих фідах верхнього шару нуль, а
    # влітку його не буде в жодному фіді, отже кожен запит із верхнім шаром давав
    # порожнечу замість образу з названою дірою.
    # ЩО ЦЕ МІНЯЄ: порожній ОБОВʼЯЗКОВИЙ слот (верх/низ/сукня) далі валить збірку —
    # без низу образу справді нема. Порожній НЕОБОВʼЯЗКОВИЙ слот тепер випадає, а
    # діра їде у вихід як `слоти_випали`, і K-WEA-01 має що сказати людині.
    необовʼязкові = tuple(kw.pop("необовʼязкові", None) or СЛОТИ_НЕОБОВЯЗКОВІ)
    # СІД ПРОГОНУ. `pop`, а не `get`: далі kw цілим іде в `pipeline.перевірити_образ`,
    # і зайвий ключ там був би не входом сценарію, а сміттям.
    сід = int(kw.pop("сід", СІД_ВИБІРКИ) or 0)
    # ── ВИМІР: N ОЦІНЕНИХ ОБРАЗІВ ДЛЯ ТЕСТІВ, НЕ ДЛЯ ПРОДУКТУ ────────────────
    # `вимір=N` додає у вихід `_оцінені` — N реальних образів із пулу, кожен уже
    # оцінений. Це НЕ повернення власного перебору: перебір був декартовим
    # добутком по всіх слотах і вбивав процес по пам'яті на шістнадцяти слотах.
    # Тут — вибірка сталого розміру з окремого модуля `вимір_правил`.
    # ПРОДУКТ ЦЬОГО НЕ ПЕРЕДАЄ НІКОЛИ: `bridge` не знає цього параметра, і на це
    # стоїть гейт. Питання «чи правило хоч раз спрацювало на речах із фіду» живе;
    # зникло лише джерело образів, і воно відновлене тут, а не в продуктовому шляху.
    _вимір = int(kw.pop("вимір", 0) or 0)
    _сцен_пулу = {k: kw.get(k) for k in ("місце", "нагода", "година", "темп_c", "дрес_код", "_ошатність", "intent",
                                         "траур", "траур_заяви", "прикраси")}
    речі, відкинуто = _придатні(каталог, жорстке_ні, вето, тіло, сцен=_сцен_пулу)
    # ── ТРАУРНИЙ РЕГІСТР ПУЛУ — У ВИХІД (рядок 154): що діяло і скільки знято по слотах.
    # Читачі — `міст_пакет._пакет_у_бюджет` (той самий регістр для добору
    # обов'язкового слота, лічба у `відсічено`, мітка пакета для суду й картки).
    import траурний_регістр as _ТР
    _траур_пулу = _ТР.траур_сцени(kw)      # за заявою людини, не за нагодою поломки руки 2
    _зняв_траур = [x for x in відкинуто if str(x.get("причина") or "").startswith("траурна нагода")]
    # ── СМУГА ОШАТНОСТІ НАГОДИ — ТИМ САМИМ СВІДКОМ, ЩО Й ВІДСІВ ЗІ СЦЕНИ ─────
    # (рядок 119, 21.09.2026.) `_придатні` уже звіряє формальність ТИПУ зі сценою
    # з допуском корпусу; тут та сама смуга їде в добір слота верхнього шару, де
    # допуску нема: слот, який дрес-код УТРИМАВ понад температурну мапу, не має
    # права наповнюватись денним гардеробом (`_за_ошатністю_нагоди`).
    _смуга_нагоди = смуга_нагоди(_сцен_пулу)

    по_слотах, ноти = {}, {}
    _лічби_ошатності = {}
    if _нота_шару:
        ноти["верхній_шар"] = _нота_шару
    # ── ПРИКРАСИ З ЦИМ ОБРАЗОМ (рядок 108): її слово про сьогодні ───────────
    # «без прикрас» — ювелірні слоти ЗНЯТО з переліку: це не порожній слот
    # («нема речі» ≠ «річ не потрібна» — див. `випали` нижче), а її рішення, тож
    # ані ноти «слот ВИПАВ», ані знахідки «порожній слот» тут нема — лише
    # причина словом. Метал (золото/срібло/інші) іде фільтром у сам добір слота.
    _прикраси = str(kw.get("прикраси") or "").strip().lower()
    if _прикраси == "без прикрас":
        import feed as _Ф_
        _зняті = tuple(с for с in слоти if с in _Ф_._МЕТАЛ_СЛОТИ)
        слоти = tuple(с for с in слоти if с not in _Ф_._МЕТАЛ_СЛОТИ)
        for с in _зняті:
            ноти[с] = "слот ЗНЯТО за її словом «без прикрас» — не брак каталогу і не порожній слот"
    for сл in слоти:
        к, нота, лічба = _кандидати_на_слот(речі, вікна, сл, сід,
                                            реєстр_людини=kw.get("реєстр_людини"),
                                            прикраси=(_прикраси or None),
                                            ошатність=_смуга_нагоди)
        # ПОРОЖНЬО ЧЕРЕЗ ТРАУРНИЙ РЕГІСТР — ЦЕ ВІДПОВІДЬ, А НЕ «НЕМА РЕЧЕЙ» (рядок 154).
        # Доти порожній слот казав «після абсолютних фільтрів» і мовчав, котрий із
        # них спорожнив слот; тут причину названо разом із тим, скільки знято.
        _зняв_сл = sum(int((x.get("слоти") or {}).get(сл) or 0) for x in _зняв_траур)
        if not к and _зняв_сл:
            нота = ("траурний регістр: у каталозі для слота нема жодної речі, темної й тихої "
                    "без святкових оздоб — знято %d (%s). Слот лишається порожнім: світла чи "
                    "святкова річ на цій нагоді — не образ"
                    % (_зняв_сл, "; ".join("%s %d" % (x["причина"][len("траурна нагода: "):],
                                                      (x.get("слоти") or {}).get(сл))
                                           for x in _зняв_траур if (x.get("слоти") or {}).get(сл))))
        по_слотах[сл] = к
        # ДВІ ПРИЧИНИ НА ОДИН СЛОТ НЕ ЗАТИРАЮТЬ ОДНА ОДНУ (рядок 119): нота
        # температурних воріт («шар ЛИШЕНО попри 18 °C: дрес-код») стоїть тут ДО
        # добору, а нота добору («придатної за формальністю нема») приходить після.
        # Присвоєння затирало першу — і на картку їхала половина пояснення.
        if нота: ноти[сл] = ((ноти[сл] + " · ") if ноти.get(сл) else "") + нота
        if лічба: _лічби_ошатності[сл] = лічба
    # ── СМІЛИВИЙ НАМІР: гілки «на межі» в кожному слоті й один слот розриву ──────
    намір = kw.get("intent") or "conventional"
    розрив = None
    if намір in СМІЛИВІ_НАМІРИ:
        межа = kw.get("вікна_на_межі")
        if межа is None:
            # вікна межових гілок рахуються на ТІЙ САМІЙ сцені, що й ядро
            # (K-COND-04): інакше ядро судилось би за відстанню, а межа — ні.
            межа = _вікна_на_межі(
                F, слоти, намір, вікна,
                дистанція=_ДИСТ.з_сценарію(dict(місце=kw.get("місце"),
                                                формат=kw.get("формат"),
                                                нагода=kw.get("нагода"))).get("дистанція"))
        усі_вікна = list(вікна or []) + list(межа or [])
        for сл in слоти:
            ядро_ід = {r.get("group_id") or r.get("id") for r in по_слотах[сл]}
            _межові = _кандидати_гілки(речі, межа, сл, ядро_ід, ГІЛКА_МЕЖА, K_ГІЛКИ, сід)
            по_слотах[сл] = по_слотах[сл] + _межові
            # ── ПОРОЖНЯ ГІЛКА МУСИТЬ НАЗВАТИСЬ, А НЕ ЗНИКНУТИ ────────────────
            # ЩО ЦЕ МІНЯЄ (before/after, каталог_повний, statement, сід 42):
            #   before — у слоті «сумка» 248 речей ядра і НУЛЬ «на межі». Ззовні
            #            це невідрізненно від «гілка не рахувалась»: ні ноти, ні
            #            сліду. Саме на цьому місці стояв відкритий червоний.
            #   after  — слот несе рядок із причиною й числом.
            # ЧОМУ ЦЕ НЕ ПОМИЛКА КОДУ, А ФАКТ КАТАЛОГУ. «На межі» = влучає у
            # вікно ІНШОЇ гами цієї людини й НЕ влучає в ядрову. Поки ядровий пул
            # був 5 речей, у гілку падало все, що не втрапило в топ-5, — і вона
            # виглядала населеною завжди. При повному пулі (K_НА_СЛОТ=500) видно
