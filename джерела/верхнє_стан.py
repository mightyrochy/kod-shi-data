    # ОДИН ЧИТАЧ КАНАЛУ 3 НА ВСЮ ФУНКЦІЮ: пояс потрібен двом ремонтам (K-OUT-11
    # «туго підперезати» і K-OUT-26 «власний пояс поверх»), і питати про нього двічі
    # означало б мати два різні стани того самого факту в одній знахідці.
