# Своя карта й свій опис політики (один із чотирьох різними словами, V23) переїхали
# в `реєстр_правил.ПОЛІТИКА_РЕГІСТРУ`; політику записано один раз у
# `реєстр_правил.ПОЛІТИКА_ДОК`. Гейтів у цього модуля ДВА, і в таблиці кожен несе
# рядок корпусу, що його дозволяє, плюс має константу з тіром у РЕЄСТРІ вище (без
# неї гейт не видається — Н-V23-046):
#   K-OUT-15 (тема-11:366) — вето за арифметикою, не за смаком: 900 FP × 30 г
#     холодніші за 450 × 100;
#   K-OUT-41 (тема-11:893) — плече не переробляється після пошиття.
# K-OUT-05 гейтом не був і не став, і це ЗМІСТ, а не машинерія (Н-V23-046, крок 5).
# Тема-11:126 дає йому `strong` ЛИШЕ всередині чоловічого кравецтва, «where the
# source lives and states the rule as non-negotiable», і там же прямо каже: перенос
# на жіночий блейзер під пальтом НЕПЕРЕВІРЕНИЙ — там `hint` і позначка «переніс».
# Емісія в `ремонтопридатність` — саме той перенесений випадок, і вона чесно
# виходить `hint`. Тобто карта обіцяла гейт, якого емісія не видавала НІКОЛИ:
# запис, що не виконується. Піднімати емісію до `strong` означало б застосувати
# чоловічу силу до жіночої гілки — рівно те, що тема заборонила.
# Решта — репліки. Зокрема K-OUT-20 НАВМИСНО не гейт: тренч поверх светра в −2 °C
# сухого дня носять масово, і жорсткий гейт дав би хибний провал — це каже сама тема.


def _зн(*a, **kw):
    """Знахідка верхнього шару: `реєстр_правил._зн` з реєстром констант ЦЬОГО модуля.

    Чому так: інваріант «сила ≤ верифікація» рахується в одному місці для всіх
    модулів, і для цього — теж, бо стеля тіру береться з `РЕЄСТР` через `reg`.
    """
    # `reg` — реєстр КОНСТАНТ модуля (у ньому й T1-константа `fp_входів_мін`, яка
    # дає K-OUT-15 стелю `hard`). Регістру тут більше не передають: політика одна.
    kw.setdefault("reg", РЕЄСТР)
    return _РЕЄСТР._зн(*a, **kw)


def _верхній(речі):
    """Верхній шар образу або None. Одна річ: два пальта одночасно не вдягають."""
    return next((р for р in речі if р.get("слот") == "верхній_шар"), None)


def _імʼя(р):
    """Назва речі для тексту людині: `назва`, інакше `id`, інакше «річ»; не-словник — як рядок."""
    return (р.get("назва") or р.get("id") or "річ") if isinstance(р, dict) else str(р)
