const ПРОМПТ_КОЛІР = "__ПРОМПТ_КОЛІР_ПОКАЗУ__";

const _КОРЕНІ = [["шкір","шкіра"],["skin","шкіра"],["волос","волосся"],["hair","волосся"],
                 ["кільц","кільце"],["лімбальн","кільце"],["limbal","кільце"],["ring","кільце"],
                 ["райдуж","очі"],["очі","очі"],["очей","очі"],["око","очі"],["iris","очі"],["eye","очі"]];
function _міткаПеред(фрагмент){
  let ім = null, поз = -1;
  for (const [корінь, назва] of _КОРЕНІ){
    const i = фрагмент.lastIndexOf(корінь);
    if (i > поз){ поз = i; ім = назва; }
  }
  return ім;
}
/* JSON відповіді: від першого `{` до останнього `}` — обгортка ``` і слова навколо не заважають */
function _jsonКольоруП(т){
  const поч = т.indexOf('{'), кін = т.lastIndexOf('}');
  if (поч < 0 || кін <= поч) return null;
  try{ const о = JSON.parse(т.slice(поч, кін + 1)); return (о && typeof о === 'object' && !Array.isArray(о)) ? о : null; }
  catch(_){ return null; }
}
const _hexКольоруП = v => { const м = /^#?([0-9a-f]{6})$/i.exec(String(v == null ? '' : v).trim());
                            return м ? '#' + м[1].toLowerCase() : null; };
function розібратиКолір(текст){
  const из = {шкіра:[], волосся:[], очі:null, кільце:null, освітлення:null, відмова:null, безмітки:0};
  const сире = String(текст || "");
  /* JSON ЗА СКЕЛЕТОМ (П-4): `photo` — «usable» або код причини; причина — код заяви
     (`міст_вхід.ПРИЧИНИ_ПОРТРЕТА`), речення з неї пише мовна модель (`застосуватиКольори`) */
  const о = _jsonКольоруП(сире);
  if (о && ['photo', 'skin', 'hair', 'eyes'].some(к => к in о)){
    /* перше слово-код: модель інколи переписує й підпис скелета («… — usable, or why it is not») */
    const фото = (о.photo == null || о.photo === true) ? 'usable'
      : ((String(о.photo).trim().toLowerCase().match(/^[a-z_]+/) || [''])[0] || 'unknown');
    if (фото !== 'usable'){ из.відмова = фото; return из; }
    const hexи = v => (Array.isArray(v) ? v : [v]).map(_hexКольоруП).filter(Boolean);
    из.шкіра = hexи(о.skin); из.волосся = hexи(о.hair);
    из.очі = hexи(о.eyes)[0] || null; из.кільце = hexи(о.limbal_ring)[0] || null;
    /* освітлення — кодами скелета; читає його лише звіт власника (`вхід_прогону.колір`) */
    const вид = ['none', 'yellow', 'blue'].includes(о.light_cast) ? о.light_cast : null;
    const сила = ['none', 'slight', 'strong'].includes(о.light_correction) ? о.light_correction : null;
    if (вид || сила) из.освітлення = {cast: вид, correction: сила};
    return из;
  }
  /* ЗАПАСНИЙ ШЛЯХ — рядки з hex. Розмітку прибираємо обережно: ґратка тут — не розмітка,
     а початок кольору. */
  const т = сире.replace(/\r/g, " ").replace(/[*_`>]/g, " ");
  const рг = /#([0-9a-fA-F]{6})\b/g;
  let край = 0, збіг, остання = null;
  while ((збіг = рг.exec(т)) !== null){
    const мітка = _міткаПеред(т.slice(край, збіг.index).toLowerCase()) || остання;
    край = рг.lastIndex;
    const hex = "#" + збіг[1].toLowerCase();
    if (!мітка){ из.безмітки++; continue; }
    остання = мітка;
    if (мітка === "шкіра") из.шкіра.push(hex);
    else if (мітка === "волосся") из.волосся.push(hex);
    else if (мітка === "кільце"){ if (!из.кільце) из.кільце = hex; }
    else if (!из.очі) из.очі = hex;
  }
  return из;
}
