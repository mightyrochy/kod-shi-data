/* ── КОЛЬОРИ ЛЮДИНИ ───────────────────────────────────────────────────────
   ПРОМПТ — ОГОЛОШЕННЯ ЗБИРАЧА АНГЛІЙСЬКОЮ (П-4, аудит/ПРОДУКТ.md п.12):
   `міст_вхід.ЧИТАННЯ_ПОРТРЕТА`, складене під час збірки — `build_артефакт` ставить вміст
   рядка на місце плейсхолдера. Доти тут стояв сам текст промпта українською, повз збирач.
   Даних, крім фото, у виклику нема, тож і Pyodide на знайомстві йому не потрібен; той самий
   рядок бачить ручний шлях («Скопіювати запит»).
   ВІДПОВІДЬ — JSON за скелетом оголошення; читає її реєстр (`колір`, форма PORTRAIT_COLOURS): відповідь, що JSON-ом не
   стала (чат-помічник ручного шляху відповів рядками), читає запасний хід коду в Python. Pyodide піднімається
   паралельно з викликом моделі (прогрів `колір` без відповіді), тож розбір його не чекає. */
const ПРОМПТ_КОЛІР = "__ПРОМПТ_КОЛІР_ПОКАЗУ__";

/* Відповідь моделі про кольори читає РЕЄСТР, не показ: форма PORTRAIT_COLOURS (`міст_вхід.прийняти_колір` у
   Pyodide через `колір`) — розбір обгортки, схема і ОДИН повтор словами; проза з hex — розбіжність форми, не
   запасний хід коду (Е2-межі п.4). Тут доти стояв власний читач (`розібратиКолір`: від першої `{` до останньої `}`,
   рядки з мітками): модель з іншою обгорткою його ламала, а схеми й повтору не було (Е2-межі-показу, ПС-13, ПС-23).
   Показ несе текст туди й результат назад: стан «готово» | «відмова» (код причини) | «брак_точок» (+ `повтор`). */
const читатиВідповідьКольоруП = текст => містП('колір', {відповідь_моделі: текст == null ? null : String(текст)});

let КОЛІР = {шкіра:null, волосся:null, очі:null, кільце:null, точки:null};
/* Стан останнього читання кольорів — окремо від `КОЛІР`: відмова чи брак точок не стирає прочитане раніше,
   а `стан` не їде в збережений профіль. Читач — стенд (ядро_дія 'колір'). */
let СТАН_КОЛЬОРУ_П = null;
let ВІДПОВІДЬ_КОЛЬОРУ_П = '';   // сира відповідь моделі: для повторного читання після збою мосту, не для екрана
let ЧИТАННЯ_КОЛЬОРУ_П = 0;
function скинутиЧитанняКольорівП(){
  ЧИТАННЯ_КОЛЬОРУ_П++;
  ВІДПОВІДЬ_КОЛЬОРУ_П = ''; СТАН_КОЛЬОРУ_П = null;
  $('кол-повтор').hidden = true; $('кол-повтор').disabled = false;
  $('кол-зчитати').disabled = false;
  $('кол-відповідь').value = ''; $('кол-стан').textContent = '';
}
/* Відповідь належить профілю й фото, для яких її отримано (11711–11713): `ВЛАСНИК_ВІДПОВІДІ_П` — їхній відбиток;
   читає її лише `відповідьКольоруП()`, що віддає порожнє, коли профіль чи фото вже інші. `РОД_ФОТО_П` росте з кожною
   зміною портрета чи профілю, тож відповідь, що надійшла вже після зміни, не записується. */
let РОД_ФОТО_П = 0, ВЛАСНИК_ВІДПОВІДІ_П = null;
const відбитокВласникаП = () => АКТИВНИЙ + '|' + РОД_ФОТО_П;
function скинутиВідповідьКольоруП(){ РОД_ФОТО_П++; ВЛАСНИК_ВІДПОВІДІ_П = null; скинутиЧитанняКольорівП(); }
function записатиВідповідьКольоруП(текст, відбиток){
  if (відбиток !== відбитокВласникаП()) return;
  ВІДПОВІДЬ_КОЛЬОРУ_П = текст; ВЛАСНИК_ВІДПОВІДІ_П = відбиток;
}
function відповідьКольоруП(){ return ВЛАСНИК_ВІДПОВІДІ_П === відбитокВласникаП() ? ВІДПОВІДЬ_КОЛЬОРУ_П : ''; }

function малюватиСвотчі(){
  /* Кожна риса — свій ряд з усіма точками, обідок райдужки названо. Hex не
     показується: людина судить квадратик, число лишається в title. */
  const к = $('кол-свотчі'); к.innerHTML = '';
  const груп = [
    ['Шкіра', (КОЛІР.точки||{}).шкіра || (КОЛІР.шкіра ? [КОЛІР.шкіра] : [])],
    ['Волосся', (КОЛІР.точки||{}).волосся || (КОЛІР.волосся ? [КОЛІР.волосся] : [])],
    ['Очі', КОЛІР.очі ? [КОЛІР.очі] : []],
    ['Обідок райдужки', КОЛІР.кільце ? [КОЛІР.кільце] : []]
  ];
  for (const [назва, точки] of груп){
    if (!точки.length) continue;
    const г = ел('div', 'св-група');
    г.appendChild(елЖінціП('div', 'св-назва', назва + (точки.length > 1 ? ' — ' + точки.length + ' тони' : '')));
    const р = ел('div', 'св-ряд');
    точки.forEach(hex=>{
      const д = ел('div', 'св'); const i = ел('i'); i.style.background = hex;
      д.appendChild(i); р.appendChild(д);
    });
    г.appendChild(р); к.appendChild(г);
  }
}
async function писатиКолір(){
  try{ await писатиАктивний(); малюватиСмугу(); }
  catch(e){ збійЖінціП($('збій-стан'), 'not_saved', e); }
}
/* Кольори з портрета читає сама сторінка через міст; ручний шлях — під
   розкривачем: без мосту, при відмові моделі, або щоб перевірити очима. */
async function зчитатиКольориЗПортрета(){
  const ст = $('кол-стан'), кн = $('кол-зчитати');
  скинутиВідповідьКольоруП();
  const профіль = АКТИВНИЙ, читання = ЧИТАННЯ_КОЛЬОРУ_П;
  const своє = () => профіль === АКТИВНИЙ && читання === ЧИТАННЯ_КОЛЬОРУ_П;
  let блоб = null;
  const відб = відбитокВласникаП();
  try{ блоб = await читатиКв(ключФото('портрет')); }
  catch(e){ if (своє()) збійЖінціП(ст, 'photo_unreadable', e); return; }
  if (!своє()) return;
  if (!блоб){ ст.textContent = 'Спершу додай портрет — він вище на цьому ж екрані.'; return; }
  if (!(МІСТ_П.адреса && МІСТ_П.токен) && /^https?:$/.test(location.protocol) && location.origin !== 'null'){
    ст.textContent = 'Нема токена доступу. Відкрий Люстерко з посилання, яке дав власник (…/kod-shi-data/#токен), або скористайся іншим шляхом нижче.';
    return;
  }
  ВІДПОВІДЬ_КОЛЬОРУ_П = ''; $('кол-повтор').hidden = true;
  кн.disabled = true; ст.textContent = 'Стилістка дивиться на портрет…';
  try{
    const її = await блобВБазу(блоб);
    if (!своє()) return;
    /* прогрів: Pyodide піднімається, поки модель дивиться на фото; збій тут нічого не вирішує —
       його покаже сам розбір нижче */
    читатиВідповідьКольоруП(null).catch(() => {});
    let відп = await модельРукиП(ПРОМПТ_КОЛІР, її);
    if (!своє()) return;
    /* сира відповідь моделі — не на екран (11240): міст не відповів — вона лишається в стані коду */
    записатиВідповідьКольоруП(відп, відб);
    let из = await читатиВідповідьКольоруП(відп);
    if (!своє()) return;
    if (из.повтор){
      /* ОДИН ПОВТОР СЛОВАМИ (реєстр: `повтор` — помилки формату JSON-ом): той самий промпт з `format_error`;
         далі — що прочиталось, і рядок про брак точок, як доти */
      ст.textContent = 'Стилістка дивиться ще раз…';
      відп = await модельРукиП(промптПовторуП(ПРОМПТ_КОЛІР, из.повтор), її);
      if (!своє()) return;
      записатиВідповідьКольоруП(відп, відб);
      из = await читатиВідповідьКольоруП(відп);
      if (!своє()) return;
    }
    await застосуватиКольори(из, своє, її);
  }catch(e){
    if (!своє()) return;
    $('кол-повтор').hidden = !відповідьКольоруП();
    збійЖінціП(ст, 'colors_failed', e);
  }finally{ if (своє()) кн.disabled = false; }
}

/* ── ВИМІР КАДРУ КОДОМ (наряд Річ-ознаки-обличчя-вимір-портрета) ──
   Модель зору дає рамки зон у тисячних (`из.зони`: щоки, лоб, волосся, райдужки), показ ріже їх із того самого кадру,
   який вона бачила (без поля, ≤ СТОРОНА_ЗОНИ_П px), а шкіру, волосся й очі міряє код (`портрет_вимір`, ендпойнт
   `колір` {виміряти}) — з розкидом; рамки лишаються з виміром (збережений кадр). Міст не відповів — виміру нема (null),
   і профіль лишається оцінкою моделі, як доти. */
const СТОРОНА_ЗОНИ_П = 64;
async function вимірПортретаП(фото, зони){
  const кадри = {};
  for (const ім of Object.keys(зони || {})){
    const п = await пікселіРечіП(фото, зони[ім], true, СТОРОНА_ЗОНИ_П);
    if (п) кадри[ім] = п;
  }
  try{ return await містП('колір', {виміряти: {кадри, рамки: зони || {}}}); }
  catch(e){ console.warn('вимір портрета не відбувся:', e); return null; }
}
async function застосуватиКольори(прочитано, перевірка, фото){
  const профіль = АКТИВНИЙ, читання = ЧИТАННЯ_КОЛЬОРУ_П;
  const своє = () => профіль === АКТИВНИЙ && читання === ЧИТАННЯ_КОЛЬОРУ_П && (!перевірка || перевірка());
  if (прочитано && прочитано.currentTarget === $('кол-повтор')){
    const відповідь = відповідьКольоруП(), кн = $('кол-повтор');
    if (!відповідь) return;
    кн.disabled = true;
    try{
      const результат = await читатиВідповідьКольоруП(відповідь);
      if (!своє()) return;
      кн.hidden = true;
      await застосуватиКольори(результат, своє);
    }catch(e){ if (своє()) збійЖінціП($('кол-стан'), 'colors_failed', e); }
    finally{ if (своє()) кн.disabled = false; }
    return;
  }
  const ст = $('кол-стан');
  /* `прочитано` — результат реєстру від автоматичного шляху; ручний (кнопка «Застосувати кольори») бере поле як є,
     а порожнє поле — збережену відповідь моделі зі стану: після збою мосту читання повторюється без нового виклику
     моделі (11438, рішення 11240) */
  let из;
  try{
    из = (прочитано && typeof прочитано === 'object' && 'стан' in прочитано)
      ? прочитано : await читатиВідповідьКольоруП($('кол-відповідь').value.trim() || відповідьКольоруП());
  }catch(e){
    if (!своє()) return;
    /* міст (Pyodide) не піднявся: ручна відповідь лишається в полі, причина — кодом у стані */
    СТАН_КОЛЬОРУ_П = {стан: "міст_не_відповів", причина: String((e && e.message) || e).slice(0, 160)};
    збійЖінціП(ст, 'colors_failed', e);   /* причина — у СТАН_КОЛЬОРУ_П і журналі збоїв, жінці — шаблон (#2223) */
    завершитиДіюЯдра('колір', СТАН_КОЛЬОРУ_П);
    return;
  }
  if (!своє()) return;
  if (из.відмова){
    /* ПРИЧИНА — КОДОМ, РЕЧЕННЯ — МОВНА МОДЕЛЬ (П-4, аудит/ПРОДУКТ.md п.12): доти рядком тут стояли слова
       самої функціональної моделі. Без моделі шару рядка причини нема — лишається сталий напис
       екрана і ручний шлях нижче; незнайомий код міст мови відкидає сам (`незнайомі`). */
    СТАН_КОЛЬОРУ_П = {стан: "відмова", відмова: из.відмова};
    ст.textContent = 'Стилістка відмовилась читати це фото.';
    const м = await повідомленнямП({портрет: {kind: 'portrait_unreadable', statements: [{code: из.відмова}]}},
                                   'intro.portrait');
    if (!своє()) return;
    if ((м.тексти || {}).портрет) текстЖінціП(ст, ст.textContent + ' ' + м.тексти.портрет, undefined, своїЕкрануП());
    завершитиДіюЯдра('колір', СТАН_КОЛЬОРУ_П);
    return;
  }
  /* стан — від реєстру: кольори без коду «photo» (нема чи `true`) — теж брак, не «придатне» (Е2-межі п.4, 14433) */
  if (из.стан !== 'готово' || !из.шкіра.length || !из.волосся.length || !из.очі){
    СТАН_КОЛЬОРУ_П = {стан: "брак_точок"};
    const брак = [!из.шкіра.length && 'шкіри', !из.волосся.length && 'волосся', !из.очі && 'очей'].filter(Boolean);
    текстЖінціП(ст, 'У відповіді немає: ' + (брак.length ? брак.join(', ') : 'оцінки фото')
      + '. Встав відповідь чату цілком, як є.');
    завершитиДіюЯдра('колір', СТАН_КОЛЬОРУ_П);
    return;
  }
  /* вимір — лише з кадру, який бачила модель (автоматичний шлях); ручна відповідь у полі кадру не має */
  const вимір = фото ? await вимірПортретаП(фото, из.зони) : null;
  if (!своє()) return;
  const виміряно = !!(вимір && вимір.стан === 'вимір');
  КОЛІР = {шкіра:из.шкіра[0], волосся:из.волосся[0], очі:из.очі, кільце:из.кільце,
           точки:{шкіра:из.шкіра, волосся:из.волосся}, освітлення:из.освітлення,
           вимір: виміряно ? вимір : null};
  СТАН_КОЛЬОРУ_П = {стан: "готово", вимір: вимір ? вимір.стан : null, причини_виміру: (вимір && вимір.причини) || []};
  await писатиКолір();
  if (!своє()) return;
  малюватиСвотчі();
  const ч = n=> n === 1 ? 'точка' : (n < 5 ? 'точки' : 'точок');
  const т = n=> n === 1 ? 'тон' : (n < 5 ? 'тони' : 'тонів');
  if (виміряно){
    текстЖінціП(ст, 'Кольори виміряно з фото: шкіра, волосся й очі.');
  }else{
    текстЖінціП(ст, 'Прочитано: ' + из.шкіра.length + ' ' + ч(из.шкіра.length)
      + ' шкіри, ' + из.волосся.length + ' ' + т(из.волосся.length)
      + (из.кільце ? ', обідок райдужки' : '') + '.');
    /* ворота виміру не пройдено — кольори лишаються оцінкою на око, а жінці сказано, який портрет надіслати:
       причина — кодами (`портрет_вимір.ПРИЧИНИ_ВИМІРУ`), речення — мовна модель (п.12) */
    if (вимір && (вимір.причини || []).length){
      const м = await повідомленнямП({портрет: {kind: 'portrait_unmeasured',
                                              statements: вимір.причини.map(code => ({code}))}}, 'intro.portrait');
      if (!своє()) return;
      текстЖінціП(ст, ст.textContent + ' ' + (((м.тексти || {}).портрет) || НАПИС_БЕЗ_ШАРУ_П.portrait_unmeasured),
                  undefined, своїЕкрануП());
    }
  }
  завершитиДіюЯдра('колір', СТАН_КОЛЬОРУ_П);
}
