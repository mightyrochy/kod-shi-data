function малюватиСвотчі(){
  /* Кожна риса — свій ряд з усіма точками, обідок райдужки названо. Hex не
     показується: людина судить квадратик, число лишається в title. */
  const к = $('кол-свотчі'); к.innerHTML = '';
  const груп = [
    ['Шкіра', (КОЛІР.точки||{}).шкіра || (КОЛІР.шкіра ? [КОЛІР.шкіра] : [])],
    ['Волосся', (КОЛІР.точки||{}).волосся || (КОЛІР.волосся ? [КОЛІР.волосся] : [])],
    ['Очі', КОЛІР.очі ? [КОЛІР.очі] : []],
    ['Обідок райдужки', КОЛІР.кільце ? [КОЛІР.кільце] : []]
  ];
  for (const [назва, точки] of груп){
    if (!точки.length) continue;
    const г = ел('div', 'св-група');
    г.appendChild(ел('div', 'св-назва', назва + (точки.length > 1 ? ' — ' + точки.length + ' тони' : '')));
    const р = ел('div', 'св-ряд');
    точки.forEach(hex=>{
      const д = ел('div', 'св'); const i = ел('i'); i.style.background = hex; i.title = hex;
      д.appendChild(i); р.appendChild(д);
    });
    г.appendChild(р); к.appendChild(г);
  }
}
