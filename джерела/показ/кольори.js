async function зчитатиКольориЗПортрета(){
  скинутиВідповідьКольоруП();
  показКольоруП({біля: 'зчитати'});
  const профіль = АКТИВНИЙ, читання = ЧИТАННЯ_КОЛЬОРУ_П;
  const своє = () => профіль === АКТИВНИЙ && читання === ЧИТАННЯ_КОЛЬОРУ_П;
  let блоб = null;
  const відб = відбитокВласникаП();
  try{ блоб = await читатиКв(ключФото('портрет')); }
  catch(e){ if (своє()) збійКольоруП('збій_фото', 'photo_unreadable', e); return; }
  if (!своє()) return;
  if (!блоб){ показКольоруП({напис: {код: 'нема_портрета'}}); return; }
  if (!(МІСТ_П.адреса && МІСТ_П.токен) && /^https?:$/.test(location.protocol) && location.origin !== 'null'){
    показКольоруП({напис: {код: 'нема_токена'}});
    return;
  }
  ВІДПОВІДЬ_КОЛЬОРУ_П = '';
  показКольоруП({повтор: false, читає: true, напис: {код: 'дивиться'}});
  try{
    const її = await блобВБазу(блоб);
    if (!своє()) return;
    /* прогрів: Pyodide піднімається, поки модель дивиться на фото; збій тут нічого не вирішує —
       його покаже сам розбір нижче */
    читатиВідповідьКольоруП(null).catch(() => {});
    let відп = await модельРукиП(ПРОМПТ_КОЛІР, її);
    /* портрет не дійшов — кольори не прочитано з нього: збій читання, а не «прочитано» наосліп */
    кадрівНеДійшлоП('portrait_colors');
    if (!своє()) return;
    /* сира відповідь моделі — не на екран (11240): міст не відповів — вона лишається в стані коду */
    записатиВідповідьКольоруП(відп, відб, її);
    let из = await читатиВідповідьКольоруП(відп);
    if (!своє()) return;
    if (из.повтор){
      /* ОДИН ПОВТОР СЛОВАМИ (реєстр: `повтор` — помилки формату JSON-ом): той самий промпт з `format_error`;
         далі — що прочиталось, і рядок про брак точок, як доти */
      показКольоруП({напис: {код: 'дивиться_ще'}});
      відп = await модельРукиП(промптПовторуП(ПРОМПТ_КОЛІР, из.повтор), її);
      кадрівНеДійшлоП('portrait_colors_retry');
      if (!своє()) return;
      записатиВідповідьКольоруП(відп, відб, її);
      из = await читатиВідповідьКольоруП(відп);
      if (!своє()) return;
    }
    await застосуватиКольори(из, своє, її);
  }catch(e){
    if (!своє()) return;
    показКольоруП({повтор: !!відповідьКольоруП()});
    збійКольоруП('збій_читання', 'colors_failed', e);
  }finally{ if (своє()) показКольоруП({читає: false}); }
}

/* ── ВИМІР КАДРУ КОДОМ (наряд Річ-ознаки-обличчя-вимір-портрета) ──
   Модель зору дає рамки зон у тисячних (`из.зони`: щоки, лоб, волосся, райдужки), показ ріже їх із того самого кадру,
   який вона бачила (≤ СТОРОНА_ЗОНИ_П px; волосся — з полем ПОЛЕ_ВОЛОССЯ_П і ядром ≤ СТОРОНА_ВОЛОССЯ_П px, щоб код
   перевірив стійкість контрасту до зсуву рамки волосся), а шкіру, волосся й очі міряє код (`портрет_вимір`, ендпойнт
   `колір` {виміряти}) — з розкидом; рамки лишаються з виміром (збережений кадр). Міст не відповів — стан
   «міст_не_відповів» з причиною (у СТАН_КОЛЬОРУ_П), виміру нема, і профіль лишається оцінкою моделі, як доти. */
const СТОРОНА_ЗОНИ_П = 64;
const СТОРОНА_ВОЛОССЯ_П = 96;
const ПОЛЕ_ВОЛОССЯ_П = 0.5;
async function вимірПортретаП(фото, зони){
  const кадри = {};
  for (const ім of Object.keys(зони || {})){
    const п = ім === 'волосся'
      ? await пікселіРечіП(фото, зони[ім], false, СТОРОНА_ВОЛОССЯ_П, ПОЛЕ_ВОЛОССЯ_П)
      : await пікселіРечіП(фото, зони[ім], true, СТОРОНА_ЗОНИ_П);
    if (п) кадри[ім] = п;
  }
  /* жодної зони не вирізано (модель рамок не дала чи кадр не розкодувався) — виміру нема, а не «поза воротами»:
     сказати жінці «надішли інше фото» тут нема підстав */
  if (!Object.keys(кадри).length) return null;
  try{ return await містП('колір', {виміряти: {кадри, рамки: зони || {}}}); }
  catch(e){ return {стан: 'міст_не_відповів', причини: [], причина: String((e && e.message) || e).slice(0, 160)}; }
}
/* «Повторити читання кольорів»: збережену відповідь моделі читає реєстр ще раз, без нового виклику моделі; повтор
   після збою мосту міряє той самий кадр — вимір теж іде мостом і тоді не відбувся. */
async function повторитиЧитанняКольорівП(){
  const профіль = АКТИВНИЙ, читання = ЧИТАННЯ_КОЛЬОРУ_П;
  const своє = () => профіль === АКТИВНИЙ && читання === ЧИТАННЯ_КОЛЬОРУ_П;
  const відповідь = відповідьКольоруП();
  if (!відповідь) return;
  показКольоруП({біля: 'повтор', повторює: true});
  try{
    const результат = await читатиВідповідьКольоруП(відповідь), фото = фотоДійшлоВідповідіКольоруП();
    if (!своє()) return;
    показКольоруП({повтор: false});
    await застосуватиКольори(результат, своє, фото);
  }catch(e){ if (своє()) збійКольоруП('збій_читання', 'colors_failed', e); }
  finally{ if (своє()) показКольоруП({повторює: false}); }
}
/* Ручний шлях — «Застосувати кольори»: відповідь чат-помічника, вставлена в поле (екран дає її рядком). */
const застосуватиВідповідьЧатуП = вставлено => застосуватиКольори(null, null, null, String(вставлено == null ? '' : вставлено));
/* ── ЇЇ КОЛЬОРИ — ОДНЕ МІСЦЕ, ДЕ ВОНИ ВИРІШУЮТЬСЯ (наряд Річ-ознаки-обличчя-вимір-до-читачів) ──
   Її кольори мають кількох читачів: плитки профілю й екран «Палітра», вхід вибору палітри (стилістка), вхід збирання й
   оцінки (`вхідМостаП`), помади, руки 3–4 (hex у запиті), Python-міст (`міст_вхід.features`). Доти кожен брав їх своїм
   шляхом: `застосуватиКольори` клав у `КОЛІР.шкіра` hex моделі й окремо `КОЛІР.вимір`, тож плитки й hex запитів лишались
   оцінкою моделі під написом «виміряно», а один із читачів (`вхідСтилісткиП`) виміру не передавав зовсім (дошка 16667,
   16669). Тепер рішення — тут: стан «вимір» — `шкіра`, `волосся`, `очі` суть виміряні hex (`портрет_вимір.виміряти`),
   обідок райдужки з hex моделі не домішується (одне джерело на профіль, як у `міст_вхід._features_виміру`); інакше —
   оцінка моделі, `походження` «оцінка_моделі». Читачі беруть `КОЛІР` як є, без власних копій. */
function кольориПрофілюП(из, вимір, джерело){
  const є = р => !!(вимір && вимір[р] && вимір[р].hex);
  if (вимір && вимір.стан === 'вимір' && є('шкіра') && є('волосся') && є('очі')){
    return {шкіра: вимір.шкіра.hex, волосся: вимір.волосся.hex, очі: вимір.очі.hex, кільце: null,
            точки: {шкіра: [вимір.шкіра.hex], волосся: [вимір.волосся.hex]}, освітлення: из.освітлення,
            вимір, походження: 'вимір', джерело};
  }
  return {шкіра: из.шкіра[0], волосся: из.волосся[0], очі: из.очі, кільце: из.кільце,
          точки: {шкіра: из.шкіра, волосся: из.волосся}, освітлення: из.освітлення,
          вимір: null, походження: 'оцінка_моделі', джерело};
}
async function застосуватиКольори(прочитано, перевірка, фото, вставлено){
  const профіль = АКТИВНИЙ, читання = ЧИТАННЯ_КОЛЬОРУ_П;
  const своє = () => профіль === АКТИВНИЙ && читання === ЧИТАННЯ_КОЛЬОРУ_П && (!перевірка || перевірка());
  /* ручний шлях: відповідь стоїть під кнопкою «Застосувати кольори»; автоматичний і повтор — під своїми */
  const ручний = вставлено != null;
  /* рядок під кнопкою каже «читаю» одразу з дотику: відповідь читає Python, і поки він зайнятий (перші десятки секунд
     після відкриття сторінки), біля кнопки нічого не мінялось — жінка гортала вгору шукати, чи спрацювало (живий
     прогін 14.11, с3 і с4: вада 4 після латки) */
  if (ручний) показКольоруП({біля: 'читати', напис: {код: 'читає_відповідь'}});
  /* джерело кольорів — для кроку «Що тобі до лиця»: відповідь, вставлена в поле, — з чату; порожнє поле бере
     збережену відповідь моделі на портрет, як і автоматичний шлях */
  const джерело = ручний && вставлено.trim() ? 'чат' : 'портрет';
  /* `прочитано` — результат реєстру від автоматичного шляху; ручний (кнопка «Застосувати кольори») бере поле як є,
     а порожнє поле — збережену відповідь моделі зі стану: після збою мосту читання повторюється без нового виклику
     моделі (11438, рішення 11240) */
  let из;
  try{
    из = (прочитано && typeof прочитано === 'object' && 'стан' in прочитано)
      ? прочитано : await читатиВідповідьКольоруП((вставлено || '').trim() || відповідьКольоруП());
  }catch(e){
    if (!своє()) return;
    /* міст (Pyodide) не піднявся: ручна відповідь лишається в полі, причина — кодом у стані */
    СТАН_КОЛЬОРУ_П = {стан: "міст_не_відповів", причина: String((e && e.message) || e).slice(0, 160)};
    збійКольоруП('збій_читання', 'colors_failed', e);   /* причина — у СТАН_КОЛЬОРУ_П і журналі збоїв, жінці — шаблон (#2223) */
    завершитиДіюЯдра('колір', СТАН_КОЛЬОРУ_П);
    return;
  }
  if (!своє()) return;
  if (из.відмова){
    /* ПРИЧИНА — КОДОМ, РЕЧЕННЯ — МОВНА МОДЕЛЬ (П-4, аудит/ПРОДУКТ.md п.12): доти рядком тут стояли слова
       самої функціональної моделі. Без моделі шару рядка причини нема — лишається сталий напис
       екрана і ручний шлях нижче; незнайомий код міст мови відкидає сам (`незнайомі`). */
    СТАН_КОЛЬОРУ_П = {стан: "відмова", відмова: из.відмова};
    показКольоруП({напис: {код: 'відмова'}});
    const м = await повідомленнямП({портрет: {kind: 'portrait_unreadable', statements: [{code: из.відмова}]}},
                                   'intro.portrait');
    if (!своє()) return;
    if ((м.тексти || {}).портрет) показКольоруП({напис: {код: 'відмова', шар: м.тексти.портрет}});
    завершитиДіюЯдра('колір', СТАН_КОЛЬОРУ_П);
    return;
  }
  /* стан — від реєстру: кольори без коду «photo» (нема чи `true`) — теж брак, не «придатне» (Е2-межі п.4, 14433) */
  if (из.стан !== 'готово' || !из.шкіра.length || !из.волосся.length || !из.очі){
    СТАН_КОЛЬОРУ_П = {стан: "брак_точок"};
    показКольоруП({напис: {код: 'брак', шкіри: из.шкіра.length, волосся: из.волосся.length, очі: !!из.очі}});
    завершитиДіюЯдра('колір', СТАН_КОЛЬОРУ_П);
    return;
  }
  /* вимір — лише з кадру, який бачила модель (автоматичний шлях); ручна відповідь у полі кадру не має */
  const вимір = фото ? await вимірПортретаП(фото, из.зони) : null;
  if (!своє()) return;
  КОЛІР = кольориПрофілюП(из, вимір, джерело);
  const виміряно = КОЛІР.походження === 'вимір';
  const причини = (вимір && вимір.причини) || [];
  const світло = !виміряно && причини.includes('portrait_uneven_light') ? {шар: ''} : null;
  показКольоруП({світло_портрета: світло});
  СТАН_КОЛЬОРУ_П = {стан: "готово", вимір: вимір ? вимір.стан : null, причини_виміру: причини,
                    ...(вимір && вимір.причина ? {причина_виміру: вимір.причина} : {})};
  await писатиКолір();
  if (!своє()) return;
  if (виміряно){
    показКольоруП({напис: {код: 'виміряно'}});
  }else{
    const прочитано_ = {код: 'прочитано', шкіри: из.шкіра.length, волосся: из.волосся.length, обідок: !!из.кільце, ручний};
    показКольоруП({напис: прочитано_});
    /* ворота виміру не пройдено — кольори лишаються оцінкою на око, а жінці сказано, який портрет надіслати:
       причина — кодами (`портрет_вимір.ПРИЧИНИ_ВИМІРУ`), речення — мовна модель (п.12); без її речення — сталий
       напис екрана */
    if (причини.length){
      const м = await повідомленнямП({портрет: {kind: 'portrait_unmeasured',
                                              statements: причини.map(code => ({code}))}}, 'intro.portrait');
      if (!своє()) return;
      if (світло){
        /* Загальний текст місця показу містить також шаблони для неперекладених заяв. Пораду
           про світло можна замінити лише прийнятим текстом саме цієї причини. */
        const прийняті = (м.заяви || []).filter(з => з.повідомлення === 'портрет' && з.вид === 'portrait_unmeasured'
          && з.показано && з.стан === 'translated' && з.текст?.trim());
        const шар = прийняті.map(з => з.текст).join(' ');
        const перекладено_світло = прийняті.some(з => з.заяви.some(причина => причина.code === 'portrait_uneven_light'));
        if (ПОКАЗ_КОЛЬОРУ_П.світло_портрета === світло && шар)
          показКольоруП({світло_портрета: {шар, перекладено_світло}});
      }else{
        const шар = (м.тексти || {}).портрет || '';
        показКольоруП({напис: Object.assign({}, прочитано_, {що_надіслати: true, шар})});
      }
    }
  }
  завершитиДіюЯдра('колір', СТАН_КОЛЬОРУ_П);
}
