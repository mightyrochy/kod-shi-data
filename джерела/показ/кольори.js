/* ── КОЛЬОРИ ЛЮДИНИ ───────────────────────────────────────────────────────
   ПРОМПТ — ОГОЛОШЕННЯ ЗБИРАЧА АНГЛІЙСЬКОЮ (П-4, аудит/ПРОДУКТ.md п.12):
   `міст_вхід.ЧИТАННЯ_ПОРТРЕТА`, складене під час збірки — `build_артефакт` ставить вміст
   рядка на місце плейсхолдера. Доти тут стояв сам текст промпта українською, повз збирач.
   Даних, крім фото, у виклику нема, тож і Pyodide на знайомстві йому не потрібен; той самий
   рядок бачить ручний шлях («Скопіювати запит»).
   ВІДПОВІДЬ — JSON за скелетом оголошення; читає її реєстр (`колір`, форма PORTRAIT_COLOURS): відповідь, що JSON-ом не
   стала (чат-помічник ручного шляху відповів рядками), читає запасний хід коду в Python. Pyodide піднімається
   паралельно з викликом моделі (прогрів `колір` без відповіді), тож розбір його не чекає. */
const ПРОМПТ_КОЛІР = "__ПРОМПТ_КОЛІР_ПОКАЗУ__";

/* Відповідь моделі про кольори читає РЕЄСТР, не показ: форма PORTRAIT_COLOURS (`міст_вхід.прийняти_колір` у
   Pyodide через `колір`) — розбір з ремонтом форми, схема, ЗАПАСНИЙ ХІД КОДУ (рядки з hex і мітками, коли JSON не
   став) і ОДИН повтор словами. Тут доти стояв власний читач (`розібратиКолір`: від першої `{` до останньої `}`,
   рядки з мітками): модель з іншою обгорткою його ламала, а схеми й повтору не було (Е2-межі-показу, ПС-13, ПС-23).
   Показ несе текст туди й результат назад: стан «готово» | «відмова» (код причини) | «брак_точок» (+ `повтор`). */
const читатиВідповідьКольоруП = текст => містП('колір', {відповідь_моделі: текст == null ? null : String(текст)});

let КОЛІР = {шкіра:null, волосся:null, очі:null, кільце:null, точки:null};
/* Стан останнього читання кольорів — окремо від `КОЛІР`: відмова чи брак точок не стирає прочитане раніше,
   а `стан` не їде в збережений профіль. Читач — стенд (ядро_дія 'колір'). */
let СТАН_КОЛЬОРУ_П = null;

function малюватиСвотчі(){
  /* Кожна риса — свій ряд з усіма точками, обідок райдужки названо. Hex не
     показується: людина судить квадратик, число лишається в title. */
  const к = $('кол-свотчі'); к.innerHTML = '';
  const груп = [
    ['Шкіра', (КОЛІР.точки||{}).шкіра || (КОЛІР.шкіра ? [КОЛІР.шкіра] : [])],
    ['Волосся', (КОЛІР.точки||{}).волосся || (КОЛІР.волосся ? [КОЛІР.волосся] : [])],
    ['Очі', КОЛІР.очі ? [КОЛІР.очі] : []],
    ['Обідок райдужки', КОЛІР.кільце ? [КОЛІР.кільце] : []]
  ];
  for (const [назва, точки] of груп){
    if (!точки.length) continue;
    const г = ел('div', 'св-група');
    г.appendChild(ел('div', 'св-назва', назва + (точки.length > 1 ? ' — ' + точки.length + ' тони' : '')));
    const р = ел('div', 'св-ряд');
    точки.forEach(hex=>{
      const д = ел('div', 'св'); const i = ел('i'); i.style.background = hex; i.title = hex;
      д.appendChild(i); р.appendChild(д);
    });
    г.appendChild(р); к.appendChild(г);
  }
}
async function писатиКолір(){
  try{ await писатиАктивний(); малюватиСмугу(); }catch(e){}
}
/* Кольори з портрета читає сама сторінка через міст; ручний шлях — під
   розкривачем: без мосту, при відмові моделі, або щоб перевірити очима. */
async function зчитатиКольориЗПортрета(){
  const ст = $('кол-стан'), кн = $('кол-зчитати');
  let блоб = null;
  try{ блоб = await читатиКв(ключФото('портрет')); }catch(_){}
  if (!блоб){ ст.textContent = 'Спершу додай портрет — він вище на цьому ж екрані.'; return; }
  if (!(МІСТ_П.адреса && МІСТ_П.токен) && /^https?:$/.test(location.protocol) && location.origin !== 'null'){
    ст.textContent = 'Нема токена доступу. Відкрий Люстерко з посилання, яке дав власник (…/kod-shi-data/#токен), або скористайся іншим шляхом нижче.';
    return;
  }
  кн.disabled = true; ст.textContent = 'Стилістка дивиться на портрет…';
  try{
    const її = await блобВБазу(блоб);
    /* прогрів: Pyodide піднімається, поки модель дивиться на фото; збій тут нічого не вирішує —
       його покаже сам розбір нижче */
    читатиВідповідьКольоруП(null).catch(() => {});
    let відп = await модельП(ПРОМПТ_КОЛІР, її);
    /* відповідь у поле ДО читання: міст не відповів — вона лишається для ручного шляху нижче */
    $('кол-відповідь').value = відп;
    let из = await читатиВідповідьКольоруП(відп);
    if (из.повтор){
      /* ОДИН ПОВТОР СЛОВАМИ (реєстр: `повтор` — помилки формату JSON-ом): той самий промпт з `format_error`;
         далі — що прочиталось, і рядок про брак точок, як доти */
      ст.textContent = 'Стилістка дивиться ще раз…';
      відп = await модельП(промптПовторуП(ПРОМПТ_КОЛІР, из.повтор), її);
      $('кол-відповідь').value = відп;
      из = await читатиВідповідьКольоруП(відп);
    }
    await застосуватиКольори(из);
    if (!/Прочитано/.test(ст.textContent)) ст.textContent += ' Відповідь чату — під розкривачем нижче.';
  }catch(e){
    ст.textContent = 'Не вдалось: ' + String(e).slice(0,160) + ' — можна іншим шляхом нижче.';
  }finally{ кн.disabled = false; }
}

async function застосуватиКольори(прочитано){
  const ст = $('кол-стан');
  /* `прочитано` — результат реєстру від автоматичного шляху; ручний (кнопка «Прочитати») бере поле як є */
  let из;
  try{
    из = (прочитано && typeof прочитано === 'object' && 'стан' in прочитано)
      ? прочитано : await читатиВідповідьКольоруП($('кол-відповідь').value || '');
  }catch(e){
    /* міст (Pyodide) не піднявся: читача в показі нема, тож відповідь лишається в полі, а причина — кодом у стані */
    СТАН_КОЛЬОРУ_П = {стан: "міст_не_відповів", причина: String((e && e.message) || e).slice(0, 160)};
    ст.textContent = 'Не вдалось прочитати відповідь: ' + СТАН_КОЛЬОРУ_П.причина;
    завершитиДіюЯдра('колір', СТАН_КОЛЬОРУ_П);
    return;
  }
  if (из.відмова){
    /* ПРИЧИНА — КОДОМ, РЕЧЕННЯ — МОВНА МОДЕЛЬ (П-4, аудит/ПРОДУКТ.md п.12): доти рядком тут стояли слова
       самої функціональної моделі. Без моделі шару рядка причини нема — лишається сталий напис
       екрана і ручний шлях нижче; незнайомий код міст мови відкидає сам (`незнайомі`). */
    СТАН_КОЛЬОРУ_П = {стан: "відмова", відмова: из.відмова};
    ст.textContent = 'Стилістка відмовилась читати це фото.';
    const м = await повідомленнямП({портрет: {kind: 'portrait_unreadable', statements: [{code: из.відмова}]}},
                                   'intro.portrait');
    if ((м.тексти || {}).портрет) ст.textContent += ' ' + м.тексти.портрет;
    завершитиДіюЯдра('колір', СТАН_КОЛЬОРУ_П);
    return;
  }
  if (!из.шкіра.length || !из.волосся.length || !из.очі){
    СТАН_КОЛЬОРУ_П = {стан: "брак_точок"};
    ст.textContent = 'У відповіді немає: '
      + [!из.шкіра.length && 'шкіри', !из.волосся.length && 'волосся', !из.очі && 'очей']
        .filter(Boolean).join(', ') + '. Встав відповідь чату цілком, як є.';
    завершитиДіюЯдра('колір', СТАН_КОЛЬОРУ_П);
    return;
  }
  КОЛІР = {шкіра:из.шкіра[0], волосся:из.волосся[0], очі:из.очі, кільце:из.кільце,
           точки:{шкіра:из.шкіра, волосся:из.волосся}, освітлення:из.освітлення};
  СТАН_КОЛЬОРУ_П = {стан: "готово"};
  await писатиКолір(); малюватиСвотчі();
  const ч = n=> n === 1 ? 'точка' : (n < 5 ? 'точки' : 'точок');
  const т = n=> n === 1 ? 'тон' : (n < 5 ? 'тони' : 'тонів');
  ст.textContent = 'Прочитано: ' + из.шкіра.length + ' ' + ч(из.шкіра.length)
    + ' шкіри, ' + из.волосся.length + ' ' + т(из.волосся.length)
    + (из.кільце ? ', обідок райдужки' : '') + '.';
  завершитиДіюЯдра('колір', СТАН_КОЛЬОРУ_П);
}
