/* ── ПАСПОРТ ЗАПИТУ — ОДИН ПИСАЧ (наряд Екран-паспорт-один-писач, оцінка Astra 18.11) ─────────────────────────
   ЩО БУЛО. Спільну змінну `ПАСПОРТ_П` (`стадії_збирання.js`) присвоювали сім місць у п'яти файлах — відновлення
   сценарію з бібліотеки двічі, дія коментаря до образу, збирання, хід розмови шаром і шляхом main, запасний хід —
   і кожне по-своєму чистило зняті межі (`почиститиВетоП`) та переносило мету на дві осі (`метаНаОсіП`), а
   `застосуватиПаспортДоЕкрана` дописував ті самі кроки в чинний паспорт на місці. Хто й коли змінив паспорт і
   які поля — простежити не було як.
   ЩО ТЕПЕР. Сам паспорт живе в замиканні нижче; `ПАСПОРТ_П` — лише читач на глобальному об'єкті (шістнадцять
   файлів читають його, як доти), присвоєння йому кидає виняток. Міняє паспорт одна функція `змінитиПаспортП(хто,
   як, дані)`:
   · `хто` — автор зміни (ключ внутрішньої мови: `розмова.шар`, `коментар`, `сценарій`…);
   · `як` — `оновити` (поля поверх чинного; `undefined` знімає поле), `замінити` (новий паспорт цілим; null —
     паспорта нема), `відновити` (`{паспорт, зміни}` зі збереженого сценарію: копія паспорта і його журнал);
   · кроки кожної зміни — ті самі для всіх писачів: давні ключі полів на чинні (`чиннийПаспортП`), мета на дві
     осі (`метаНаОсіП`), зняті дотиком межі геть з обох переліків вето (`почиститиВетоП`).
   ЖУРНАЛ ЗМІН. Кожна зміна — запис `{хто, як, поля, час}`, де `поля` — ключі, чиє значення змінилось (порівняння
   JSON). Журнал належить сценарію: зберігається з ним (`станСценарію().зміни_паспорта`), відновлюється разом із
   паспортом, а в запис вердикту їде копією в `етапи.розмова.зміни_паспорта` (`етапиРозмови`, `звіти.js`). */
const ЖУРНАЛ_ПАСПОРТА_МАКС_П = 300;   // сценарій — десятки ходів; сторінка, відкрита днями, не росте без меж
const [змінитиПаспортП, журналПаспортаП] = (() => {
  let паспорт = null, журнал = [];
  Object.defineProperty(globalThis, 'ПАСПОРТ_П', {
    get: () => паспорт,
    set: () => { throw new TypeError('ПАСПОРТ_П пише лише змінитиПаспортП (показ/паспорт_запиту.js)'); },
    configurable: false, enumerable: false});
  const кроки = п => {
    if (!п || typeof п !== 'object') return п || null;
    чиннийПаспортП(п); метаНаОсіП(п); почиститиВетоП(п);
    return п;
  };
  const змінені = (старий, новий) => {
    const с = старий || {}, н = новий || {};
    return [...new Set(Object.keys(с).concat(Object.keys(н)))]
      .filter(к => JSON.stringify(с[к]) !== JSON.stringify(н[к]));
  };
  function змінити(хто, як, дані){
    if (!хто || typeof хто !== 'string') throw new TypeError('passport_change_without_author');
    let новий;
    if (як === 'замінити') новий = кроки(дані);
    else if (як === 'оновити'){
      новий = Object.assign({}, паспорт || {}, дані || {});
      for (const [к, з] of Object.entries(дані || {})) if (з === undefined) delete новий[к];
      новий = кроки(новий);
    }
    else if (як === 'відновити'){
      const з = дані || {};
      новий = кроки(з.паспорт ? JSON.parse(JSON.stringify(з.паспорт)) : null);
      журнал = Array.isArray(з.зміни) ? з.зміни.slice(-ЖУРНАЛ_ПАСПОРТА_МАКС_П) : [];
    }
    else throw new TypeError('passport_change_unknown: ' + як);
    const поля = змінені(паспорт, новий);
    паспорт = новий;
    журнал.push({хто, як, поля, час: new Date().toISOString()});
    if (журнал.length > ЖУРНАЛ_ПАСПОРТА_МАКС_П) журнал.splice(0, журнал.length - ЖУРНАЛ_ПАСПОРТА_МАКС_П);
    return паспорт;
  }
  return [змінити, () => журнал.map(з => Object.assign({}, з, {поля: з.поля.slice()}))];
})();
