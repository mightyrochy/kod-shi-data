const ЗБІЙ_НЕ_ВІД_ПОВТОРУ = /PythonError|Traceback|OverflowError|MemoryError|RecursionError|ValueError|KeyError|IndexError|AttributeError|ZeroDivisionError|build_no_hand_finished/i;

/* ── ВІДМОВА КОДУ КАЖЕ ПРАВДИВУ ПРИЧИНУ І ЩО ЗРОБИТИ ─────────
   Приклад: «мороз мінус вісім і сніг» → модель поклала нагоду й місце
   поза довідником, код їх чесно не взяв і відмовився збирати («сценарію нема»);
   «не дійшов звʼязок, спробуй за хвилину» було б неправдою про причину і
   порадою, яка нічого не дасть. Відмова коду несе свою ознаку (`відмова_коду`) і
   своє повідомлення кодами заяв (K-IO-01, Ч-4). */
/* ── ЗБІЙ ЗБИРАННЯ — КОДИ ЗАЯВ, А НЕ АБЗАЦ КОДУ (аудит/ПРОДУКТ.md п.12) ──
   Функція віддає ПОВІДОМЛЕННЯ внутрішньою мовою, і речення з нього пише мовна
   модель (`повідомленнямП`): речення для людини код не складає. Без моделі на екрані
   стоїть сталий напис інтерфейсу (`НАПИС_БЕЗ_ШАРУ_П.assembly_refused`), а подробиця —
   у діагнозі.
   РОЗРІЗНЕННЯ ВАЖЛИВЕ: помилка В КОДІ
   детермінована (той самий профіль, сценарій і сід дадуть її знову), тож «спробуй за
   хвилину» тут було б неправдою; обрив звʼязку минає сам, і повторити варто. Розрізняє їх
   `ЗБІЙ_НЕ_ВІД_ПОВТОРУ` — він обирає КОД заяви, а не речення. */
function повідомленняЗбоюЗбиранняП(e){
  if (e && e.відмова_коду && e.повідомлення) return e.повідомлення;
  /* ВІДМОВА КОДУ БЕЗ СВОГО ПОВІДОМЛЕННЯ — ТЕЖ ДЕТЕРМІНОВАНА. Своє повідомлення має лише
     K-IO-01 («сценарію нема», Ч-4); решта відмов `запити` кидає самим текстом причини. Вони
     так само не лікуються повтором — код відмовив не випадково, — тож ознака `відмова_коду`
     веде в ту саму гілку, що й PythonError. Без цього рядка «сценарію нема» читалось би як
     обрив звʼязку («спробуй за хвилину»), тобто рівно та неправда, яку лагодив З-1а. */
  return (e && e.відмова_коду) || ЗБІЙ_НЕ_ВІД_ПОВТОРУ.test(String((e && e.message) || e))
    ? {kind: 'assembly_refused', statements: [{code: 'assembly_stumbled_on_requirements'},
        {code: 'retry_gives_same'}, {code: 'detail_is_in_verdict_report'},
        {code: 'try_other_scenario_or_drop_requirement'}]}
    : {kind: 'assembly_refused', statements: [{code: 'connection_did_not_reach'},
        {code: 'retry_in_a_minute_may_work'}]};
}

