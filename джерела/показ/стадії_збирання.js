          ...(КОРОТКИЙ_ЗАПИС_П ? {короткий_запис: 1} : {}),
          /* НЕ ОБРАНЕ НЕ ШЛЕТЬСЯ і тут (К-3, варіант «б»): 1 — це «як доти», і поля тоді нема */
          ...(ЧАСТИН_РУКИ_1_П > 1 ? {частин_руки_1: ЧАСТИН_РУКИ_1_П} : {}),
