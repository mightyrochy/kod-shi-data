    про_речі: (кя.про_речі_en || []).map(([id, текст]) => ({id, текст})),
    фото_не_ті: кя.фото_не_те || [], свідомі: (кя.свідомі || []).map(з => з.чому_en),
    без_опису: кя.збій_опису ? повідомленняБезОписуП('форма') : null,
    опис_без_фото: (кя.невідоме || []).some(з => з.код === 'description_written_without_photos')
