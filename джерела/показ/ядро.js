const ЯДРО_П = (function(){
  const хеш = new URLSearchParams(location.hash.slice(1));
  const з = (хеш.get('ядро') || хеш.get('yadro') || '').trim();
  const вибір = з === '0' || з === '1' ? з : null;
  /* Новий ключ відділяє вибір після переходу від записів із часів типового старого шляху. */
  const ключ = 'міст:ядро:v2';
  if (вибір !== null){
    try { localStorage.setItem(ключ, вибір); } catch(_){}
    return вибір !== '0';
  }
  try { return localStorage.getItem(ключ) !== '0'; } catch(_){ return true; }
})();
