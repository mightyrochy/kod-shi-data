/* ── ЕКРАН: ПРИМІРЯННЯ НА КАРТЦІ (перепис екрана, частина 8г) ─────────────────
   Логіка (`приміряння.js`: `приміряти(поз)`) вузлів не торкається. Що про приміряння видно на картці, вона тримає
   за об'єктом картки — `показПриміркиП(поз)`: `іде`, `малює`, `код` кроку чи збою, `слова` моделі, `підпис`
   кадру — і кличе ім'я `показатиПримірку(поз)`; стан екрана — лише лічильник подій за позиціями.
   Малювач `примірка` малює з цих даних усе, що на картці каже про приміряння: кнопку «Приміряти на себе» (мовчить,
   поки приміряння в дорозі), рядок під нею й питання «та сама річ?» під вердиктом. Туман на місці кадру — справа
   полотна (`малюватиПолотноКартки`, `екран/картка.js`): воно читає `малює` з тих самих даних.
   Перебудована картка (`підвʼязатиКартку`) малюється тим самим малювачем, тож кнопка й рядок не розходяться з
   тим, що діється: доти рядок і вимкнена кнопка лишались на від'єднаних вузлах. */
Екран.змінити({примірка: {}});

function показатиПримірку(поз){
  Екран.змінити({примірка: подіяПозиції(Екран.стан.примірка, поз, {})});
}

/* слова кроків: що сталось, логіка каже кодом */
const НАПИСИ_ПРИМІРКИ = {
  читаю: 'Читаю твоє фото…',
  нема_фото: 'Немає фото на повний зріст — додай його в профілі — вкладка «Профіль» унизу.',
  за_описом: 'Малюю за описом…',
  за_фото: 'Одягаю тебе в ці речі…',
  без_фото_речей: 'Крамниці не віддали жодного фото речей. Картинка була б не про ці речі — приміряння скасовано.',
  повтор: 'Вийшов не один кадр, а кілька поруч — прошу намалювати ще раз…',
  /* мовний шар пише підпис кадру: поки він працює, під кадром порожньо, а не старе «Одягаю…» */
  мова: ''};

/* «Та сама річ?» — мітка й ряд дотиків; одне на картку, чи її збудовано вже з кадром (`рендерКартку`), чи кадр
   з'явився на показаній. */
function питанняТієїСамоїРечі(поз){
  const тимч = ел('div');
  const мітка = ел('div', 'мітка', 'Це та сама річ, що на фото товару?'); мітка.id = 'річ-' + поз;
  тимч.appendChild(мітка);
  чипРяд(тимч, 'річ', поз, ['так', 'ні, намальовано інше'], ['', 'ні']);
  return [...тимч.childNodes];
}

function малюватиПримірку(поз){
  const з = показПриміркиП(поз), кн = $('прмк-' + поз), ст = $('прм-' + поз);
  if (кн) кн.disabled = !!з.іде;
  if (!ст) return;
  /* збій: слід лишила логіка (`збійЖінціП(null, …)`), тут — шаблон; ключ шаблону — літерал на кожен код */
  if (з.код === 'збій_фото') показатиШаблонЗбоюП(ст, 'photo_unreadable');
  else if (з.код === 'без_картинки') показатиШаблонЗбоюП(ст, 'tryon_no_image');
  else if (з.код === 'не_повернуто') показатиШаблонЗбоюП(ст, 'tryon_not_returned');
  else if (з.код === 'збій') показатиШаблонЗбоюП(ст, 'tryon_failed');
  /* картинки нема, модель відповіла словами — її слова йдуть з видом, як і були */
  else if (з.код === 'слова_моделі') текстЖінціП(ст, 'Картинки не вийшло: ' + з.слова, 'tryon_no_image');
  /* підпис кадру — речення мовного шару (чи складене кодом, коли шар мовчить) */
  else if (з.код === 'підпис') текстЖінціП(ст, з.підпис);
  else ст.textContent = НАПИСИ_ПРИМІРКИ[з.код] || '';
  /* тепер є що звірити — питання стає за аспектами, як у `рендерКартку` (КВ-1) */
  const к = П.картки[поз];
  if (з.код === 'підпис' && к && к.примірка && к.примірка.режим === 'за фото' && !$('річ-' + поз)){
    const аспекти = $('аспекти-' + поз);
    if (аспекти) аспекти.after(...питанняТієїСамоїРечі(поз));
  }
}
Екран.малювач('примірка', ['примірка'], (с, до) => {
  for (const поз of зПодією(с.примірка, до.примірка)) малюватиПримірку(поз);
});
