/* ── ЕКРАН: ГОЛОС ──────────────────────────────────────────────────────────
   Мікрофон біля поля — віджет екрана. Полів з мікрофоном три: розмова (`екран/розмова.js`), коментар картки образу
   (`картки.js`) і розмова з фото (`розмова_з_фото.js`); два останні малювач будує наново, і мікрофон живе рівно
   стільки, скільки його поле. Тому стан мікрофона — не ключ стану екрана, а замикання на пару «кнопка — поле»
   (вузли, яких у стані не втримати), а «слухає щонайбільше один» — стала файла `ГОЛОС_АКТИВНИЙ`. Логіки тут нема:
   слова лягають у поле подією `input` — тим самим шляхом, що з клавіатури (дія поля на ядрі чує її так само), а
   позначку «надиктовано» ставить викликач (`після`). Ім'я `привʼязатиГолос` лишено: ним водять стенди. */
/* ── ГОЛОСОВИЙ ВВІД (слово власника: «на головне поле спілкування зі
      стилісткою та на поле, де тестувальники записують вердикт») ─────────────
   ЩО ЦЕ МІНЯЄ В РІШЕННІ. Нічого — і це навмисно. Голос не додає коду жодного
   нового входу: він лише інший спосіб НАПИСАТИ те саме. Продиктоване лягає в
   поле, як із клавіатури (та сама подія `input`, ті самі обробники), і далі йде
   тим самим шляхом: репліка — через `слатиЧатП`, коментар — у
   `відповідь(поз).коментар`. НІ ОДНА ГІЛКА ТУТ НЕ НАДСИЛАЄ ТЕКСТ САМА: `слатиЧатП`
   і `записати` кличе лише дотик жінки. Розпізнане — чернетка, не рішення.

   ЧОМУ РОЗПІЗНАВАННЯ БРАУЗЕРА, А НЕ МОДЕЛЬ. Запасний шлях «записати
   `MediaRecorder` → віддати аудіо тій самій моделі» перевірено по КОДУ МОСТУ
   (`worker_джерело.js`), і він не проходить: маршрут `claude-` віддає тіло
   провайдерові як є, а Messages API блоку `audio` не має взагалі; маршрут
   `gemini-` перекладає блоки сам і знає РІВНО ДВА — `image` → `inline_data`,
   усе інше → `{text: б.text}`, тобто аудіо поїхало б як `{text: undefined}`.
   Тож аудіо через міст не пройде без правки мосту, і його тут нема.

   ЧЕСНІСТЬ (окремим рядком, не дрібним шрифтом). Фото показ обіцяє лишити на
   телефоні — голос так обіцяти не можна: розпізнає його служба браузера
   (у Chrome — Google, на iPhone — Apple), і звук іде до неї. Це сказано при
   першому ж вмиканні, разом із тим, що в поле потрапляє лише текст, який вона
   бачить і може виправити. */
/* КЛАС ЧИТАЄТЬСЯ НА КОЖЕН ДОТИК, А НЕ РАЗ НА ЗАВАНТАЖЕННЯ. Причина не в
   красі: розпізнавання приходить у сторінку по-різному (`SpeechRecognition` або
   `webkitSpeechRecognition`), а на iOS воно буває недоступним на момент
   виконання скриптів. Прочитане раз у константу означало б «нема назавжди» —
   і мертву кнопку там, де голос насправді є. Це ж робить гілку «розпізнавання
   нема» вимірною: стенд знімає клас зі `window` і тисне кнопку. */
const класГолосу = ()=> (typeof window === 'undefined') ? null
  : (window.SpeechRecognition || window.webkitSpeechRecognition || null);
/* ── ЯК З РЕЗУЛЬТАТІВ РОЗПІЗНАВАННЯ СКЛАСТИ ТЕКСТ (ГОЛОС-1) ──
   Склейка `transcript` усіх результатів без пробілів працює лише для сегментного
   потоку. На Android Chrome (continuous + interimResults) КОЖЕН результат —
   наростаюча гіпотеза («хочу», «хочу на», «хочу на вітряний»…), і склейка давала
   «хочухочу нахочу на вітряний…». Тому сегмент, що ПРОДОВЖУЄ попередній (його
   початок збігається), ЗАМІНЮЄ його; повтор (iOS повторює останній остаточний)
   пропускається; решта — новий сегмент через пробіл. Остаточне не губиться:
   сегмент витісняється лише тим, що містить його повністю або виправляє його
   останнє слово. */
function зібратиДиктування(результати){
  const норм = т => String(т || '').replace(/\s+/g, ' ').trim();
  const ключ = т => т.toLowerCase();
  const сл = т => ключ(т).split(' ').filter(Boolean);
  const сегм = [];                                    // [{т, фін}]
  for (let i = 0; i < результати.length; i++){
    const р = результати[i] || {};
    const т = норм((р[0] || {}).transcript);
    if (!т) continue;
    const ост = сегм[сегм.length - 1];
    if (ост){
      const а = ключ(ост.т), б = ключ(т);
      if (б.startsWith(а)){ ост.т = т; ост.фін = !!р.isFinal; continue; }   // наростає
      if (а === б || (ост.фін && а.endsWith(б))){ continue; }               // повтор
      if (!ост.фін && а.startsWith(б)) continue;                            // гіпотеза скоротилась
      const wa = сл(ост.т), wb = сл(т);                                     // виправлено останнє слово
      if (wa.length >= 2 && wb.length >= wa.length && wa.slice(0, -1).every((x, k) => x === wb[k])){
        ост.т = т; ост.фін = !!р.isFinal; continue;
      }
    }
    сегм.push({т, фін: !!р.isFinal});
  }
  return сегм.map(х => х.т).join(' ');
}
let ГОЛОС_ЧЕСНО_СКАЗАНО = false;   // рядок про службу — раз на сеанс, не на кожен дотик
let ГОЛОС_АКТИВНИЙ = null;         // слухає щонайбільше один мікрофон
/* Хто саме розпізнає — НАЗИВАЄТЬСЯ, а не ховається за «служба браузера». Не
   вгадується там, де не видно: невідомий браузер дістає обидві назви з умовою.
   Назва служби — імʼя латиницею, а не проза: іде частиною складеного підпису (`{назва}`), бо рядок із нею голим
   текстом точка виходу відхиляє як латинський залишок і показує «— без тексту» (15104). */
function хтоРозпізнаєГолос(){
  const ua = String((navigator && navigator.userAgent) || '');
  if (/iPad|iPhone|iPod/.test(ua) || (/Macintosh/.test(ua) && (navigator.maxTouchPoints || 0) > 1))
    return ['на цьому телефоні це ', {назва: 'Apple'}];
  if (/Edg\//.test(ua)) return ['у цьому браузері це служба ', {назва: 'Microsoft'}];
  if (/Chrome|Chromium/.test(ua)) return ['у цьому браузері це служба ', {назва: 'Google'}];
  return ['у ', {назва: 'Chrome'}, ' це служба ', {назва: 'Google'}, ', на ', {назва: 'iPhone'}, ' — ', {назва: 'Apple'}];
}
const ГОЛОС_ЧЕСНО = ()=> ['Голос розпізнає не Люстерко, а служба браузера: ', ...хтоРозпізнаєГолос(),
  ' — звук іде до неї. У поле лягає лише текст: ти його бачиш, можеш виправити, і надсилаєш сама.'];
/* Обидва написи — шаблони збою (`ШАБЛОНИ_ЗБОЮ_П`): коли розпізнавач не створився чи не стартував, той самий текст
   лягає в ноту вже зі слідом у журналі збоїв (`збійЖінціП`). */
const ГОЛОС_НЕМА = ШАБЛОНИ_ЗБОЮ_П.voice_unavailable;
const ГОЛОС_ЗАБОРОНЕНО = ШАБЛОНИ_ЗБОЮ_П.microphone_blocked;
/* Один мікрофон = одне поле. `після` кличеться, коли текст ліг у поле, — саме
   там ставиться позначка «надиктовано» для звіту. */
function привʼязатиГолос(о){
  const кнопка = о.кнопка, поле = о.поле, нота = о.нота;
  if (!кнопка || !поле) return null;
  let розп = null, слухає = false, база = '', сама_стала = false, фінальних = 0, чекаєЗапису = false, поточна = null, свійЗапис = false;
  const сказати = т => { текстЖінціП(нота, т); };
  const намалювати = ()=>{
    кнопка.classList.toggle('слухає', слухає);
    кнопка.setAttribute('aria-pressed', слухає ? 'true' : 'false');
    кнопка.setAttribute('aria-label', слухає ? 'Зупинити запис голосу' : 'Сказати голосом');
    кнопка.title = слухає ? 'Зупинити запис' : 'Сказати голосом';
  };
  /* Дописуємо до вже написаного, а не затираємо: вона могла почати з клавіатури. */
  const склеїти = т => {
    const х = String(т || '').replace(/^\s+/, '');
    if (!х) return база;
    return база && !/\s$/.test(база) ? база + ' ' + х : база + х;
  };
  const покласти = (т, завершено) => {
    /* Картку могли перемалювати під час диктування — тоді поле відʼєднане від
       документа, і писати в нього означало б губити текст мовчки. */
    if (!поле.isConnected){ поточна.дозволено = false; стати(true); return; }
    поле.value = склеїти(т);
    поточна.останній = поле.value;
    /* ТА САМА ПОДІЯ, ЩО Й З КЛАВІАТУРИ: `oninput` поля — єдине місце, де показ
       кладе текст у стан (`відповідь(поз).коментар`, ріст поля, «порожньо» на
       кнопці). Диктувати повз неї означало б завести другий шлях запису. */
    свійЗапис = true;
    try{ поле.dispatchEvent(new Event('input', {bubbles: true})); }
    finally{ свійЗапис = false; }
    /* Помилка в позначці НЕ валить диктування — але й не ковтається мовчки
       (аудит/ПРОДУКТ.md п.14): текст жінки дорожчий за позначку, а зникла позначка,
       про яку ніхто не сказав, — це наступна вада у звіті власника. */
    чекаєЗапису = !завершено;
    if (завершено && о.після) try{ о.після(поле.value); }catch(e){
      показатиЗбійЗапису('dictation_not_marked', e); }
  };
  const стати = тихо => {
    const був = розп; розп = null; слухає = false;
    /* зупинка (рукою чи самого розпізнавача) після лише проміжних гіпотез: те, що лежить у полі, — її слова,
       тож запис («надиктовано», «не ця», переклад) робимо тут, один раз */
    if (чекаєЗапису){
      чекаєЗапису = false;
      if (о.після && поле.isConnected && (поле.value || '').trim()) try{ о.після(поле.value); }catch(e){
        показатиЗбійЗапису('dictation_not_marked', e); }
    }
    if (ГОЛОС_АКТИВНИЙ === сесія) ГОЛОС_АКТИВНИЙ = null;
    if (був) try{ був.stop(); }catch(e){
      console.warn('голос: не вдалося зупинити розпізнавання: ' + String(e).slice(0, 140)); }
    намалювати();
    if (!тихо) сказати('');
  };
  /* Рука забирає поле навіть між stop() та останнім результатом браузера.
     Програмний focus і власний input диктування цього не роблять. */
  const рукою = ()=>{
    if (!поточна || !поточна.дозволено) return;
    поточна.дозволено = false; сама_стала = false;
    стати(false); база = поле.value || '';
  };
  for (const подія of ['pointerdown', 'touchstart'])
    поле.addEventListener(подія, п => { if (п.isTrusted) рукою(); });
  поле.addEventListener('input', п => {
    if (!свійЗапис && поточна && (п.isTrusted || поле.value !== поточна.останній)) рукою();
  });
  const почати = ()=>{
    const Клас = класГолосу();
    if (!Клас){ сказати(ГОЛОС_НЕМА); return; }
    if (ГОЛОС_АКТИВНИЙ && ГОЛОС_АКТИВНИЙ !== сесія) ГОЛОС_АКТИВНИЙ.стати();
    if (поточна) поточна.дозволено = false;
    база = поле.value || '';
    сама_стала = true;
    фінальних = 0; чекаєЗапису = false;
    try{
      розп = new Клас();
    }catch(e){ розп = null; збійЖінціП(нота, 'voice_unavailable', e); return; }
    const ця = поточна = {останній: база, дозволено: true};
    const належить = ()=>{
      if (поточна !== ця || !ця.дозволено) return false;
      if (поле.value !== ця.останній){ рукою(); return false; }
      return true;
    };
    розп.lang = 'uk-UA';
    розп.interimResults = true;      // проміжний текст видно в полі одразу
    розп.continuous = true;          // вона говорить реченнями, не словами
    розп.maxAlternatives = 1;
    /* Проміжне й остаточне збираються з УСІХ результатів, а не з `resultIndex`:
       у continuous вони накопичуються, і читання лише останнього губило б початок.
       Як з них скласти текст — `зібратиДиктування` (Android віддає наростаючі
       гіпотези, настільний Chrome — сегменти, iOS — ще й повтор останнього). */
    розп.onresult = п => {
      if (!належить()) return;
      const результати = Array.from(п.results || []);
      /* проміжні гіпотези лише оновлюють поле; запис («не ця», переклад) — на кожній НОВІЙ фінальній */
      const фін = результати.filter(р => !!(р && р.isFinal)).length;
      покласти(зібратиДиктування(результати), фін > фінальних);
      фінальних = Math.max(фінальних, фін);
    };
    /* iOS Safari зупиняє розпізнавання САМ (тиша, перемикання вкладки). Текст
       уже в полі й лишається там: `база` переїжджає на нього, тож наступний
       дотик ДОПИСУЄ, а не затирає. */
    розп.onend = ()=>{
      if (!належить()) return;
      ця.дозволено = false;
      const було = слухає;
      база = поле.isConnected ? (поле.value || '') : база;
      стати(true);
      if (було && сама_стала)
        сказати('Мікрофон зупинився сам — текст лишився в полі. Торкнись ще раз, щоб продовжити.');
    };
    розп.onerror = п => {
      if (!належить()) return;
      ця.дозволено = false;
      const к = String((п && п.error) || '');
      сама_стала = false;
      стати(true);
      if (к === 'not-allowed' || к === 'service-not-allowed') сказати(ГОЛОС_ЗАБОРОНЕНО);
      else if (к === 'no-speech') сказати('Не почула нічого — торкнись ще раз і скажи трохи гучніше.');
      else if (к === 'aborted') сказати('');
      else if (к === 'network') сказати('Служба розпізнавання не відповіла — надиктуй мікрофоном на клавіатурі телефона.');
      else збійЖінціП(нота, 'voice_failed', к || 'unknown');   /* код служби — у слід, не в текст: латиниці їй не показуємо */
    };
    try{ розп.start(); }catch(e){ ця.дозволено = false; розп = null; збійЖінціП(нота, 'microphone_blocked', e); return; }
    слухає = true; ГОЛОС_АКТИВНИЙ = сесія; намалювати();
    сказати(ГОЛОС_ЧЕСНО_СКАЗАНО ? 'Слухаю… торкнись кнопки, щоб зупинити.'
      : підписЗНазвоюП([...ГОЛОС_ЧЕСНО(), '\nСлухаю… торкнись кнопки, щоб зупинити.']));
    ГОЛОС_ЧЕСНО_СКАЗАНО = true;
  };
  const сесія = {стати, слухає: ()=>слухає};
  кнопка.onclick = ()=>{ if (слухає){ сама_стала = false; стати(false); } else почати(); };
  намалювати();
  return сесія;
}
