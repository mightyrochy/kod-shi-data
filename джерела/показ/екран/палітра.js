/* Чип-кнопка: спільний будівник рядів вибору (палітра, помади, речі оцінки). */
function чипП(текст, обрано, дія, зразки, додКлас){
  const ч = document.createElement('span');
  /* `додКлас` іде ПЕРЕД `вибр`: обрана рідша схема має виглядати як будь-яка
     інша обрана, тож правило вибраності перекриває стриманість. */
  ч.className = 'чип' + (додКлас ? ' ' + додКлас : '') + (обрано ? ' вибр' : '');
  ч.setAttribute('role', 'button'); ч.tabIndex = 0; станВиборуП(ч);
  const сп = (Array.isArray(зразки) ? зразки : (зразки ? [зразки] : [])).filter(Boolean);
  if (сп.length){
    const з = document.createElement('span'); з.className = 'зразки';
    сп.forEach(х=>{ const i = document.createElement('i'); i.style.background = х; з.appendChild(i); });
    ч.appendChild(з);
  }
  const тв = document.createTextNode(''); текстЖінціП(тв, текст, undefined, undefined, 'data'); ч.appendChild(тв);
  ч.onclick = дія;
  ч.onkeydown = е=>{ if (е.key === 'Enter' || е.key === ' '){ е.preventDefault(); дія(); } };
  return ч;
}

/* ── ПЕРЕМАЛЬОВУВАННЯ НЕ ВИБИВАЄ ЕКРАН З-ПІД ПАЛЬЦЯ (Н6) ──
   Ряди будуються наново не лише на її дотик: відповідь стилістки чи мовної моделі приходить, коли вона вже гортає
   й цілить у чип, а нова гама міняє число основ над рядом схем — і чип від'їжджає з-під пальця. Тому малювач
   запам'ятовує, де у вікні стояв чип (а нема — ряд) навпроти середини вікна, і після перемальовування догортає
   сторінку рівно на його зсув. Розкривач «ще N основ» лишається відкритим, фокус клавіатури — на тому самому чипі. */
const РЯДИ_ПАЛІТРИ = ['пал-гама', 'пал-основа', 'пал-схема', 'пал-стрічка', 'пал-підтон'];
function чипЗаКлючемП(ключ){
  return [...document.querySelectorAll('#пал-вибір .чип')].find(ч => ч.dataset.ключ === ключ) || null;
}
function наМісціПалітри(малювати){
  const середина = window.innerHeight / 2, видно = в => в.getClientRects().length > 0;
  const верх = в => в.getBoundingClientRect().top;
  const навпроти = в => { const п = в.getBoundingClientRect(); return п.height > 0 && п.top <= середина && п.bottom >= середина; };
  const ряд = РЯДИ_ПАЛІТРИ.map($).find(в => в && видно(в) && навпроти(в)) || null;
  const чип = ряд ? [...ряд.querySelectorAll('.чип')].find(навпроти) || null : null;
  const ключ = чип ? чип.dataset.ключ : null, було = чип ? верх(чип) : ряд ? верх(ряд) : null;
  const зФокусом = document.activeElement && document.activeElement.closest && document.activeElement.closest('#пал-вибір')
    ? document.activeElement.dataset.ключ : null;
  малювати();
  if (зФокусом){ const ч = чипЗаКлючемП(зФокусом); if (ч && ч !== document.activeElement) ч.focus({preventScroll: true}); }
  if (було == null) return;
  const якір = (ключ && чипЗаКлючемП(ключ)) || ряд;
  const зсув = видно(якір) ? верх(якір) - було : 0;
  if (Math.abs(зсув) >= 1) window.scrollBy(0, зсув);
}
/* Чип ряду палітри: дотик — названа дія з ключем чипа (одна пересилка на всі ряди); `data-ключ` — та сама пара,
   за нею чип упізнається після перемальовування. */
