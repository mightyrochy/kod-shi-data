/* ── ЕКРАН: СЛУЖБОВИЙ БЛОК, ЗМІНА АДРЕСИ Й «ЗРОЗУМІЛО» (перепис екрана, решта зрізу 9) ──
   Службовий блок (`#службове`: збірка, каталог, токени, діагноз) видно лише власникові: чи його показувати,
   логіка читає з адреси й пам'яті телефона (`читатиХеш`, прапорець `СЛУЖБОВЕ`) і кличе ім'я `показатиСлужбове()`.
   Рядок шапки `ш-рядок` малює одна функція: є пакет образів — його збірка, каталог і профіль, нема — збірка
   сторінки (`рядокЗбіркиП()`, текст складає логіка). Кличуть її малювач `образи` і подія старту
   (`показатиРядокШапки()`): доти у вузол писали двоє — `службовийРядок()` у логіці й малювач образів. */
Екран.змінити({службове: false, рядок_шапки: 0});

