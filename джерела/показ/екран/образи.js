/* ── ЕКРАН: ОБРАЗИ ─────────────────────────────────────────────────────────
   Шапка екрана образів. Поки що тут один рядок — «що код справді застосував» (`обр-межі`): жінка бачить його над
   картками, а не в службовому. Картки, вердикт і «не ця» переїдуть сюди зі старого `картки.js`.
   СТАН ЕКРАНА: `межі` — лічильник «рядок меж показати наново»: логіка кличе `показатиМежі()` після кожного запису
   паспорта (хід розмови, виклик 0 збирання, відкритий сценарій, коментар до картки) і перед показом карток.
   Що сказати, логіка каже прапорцями (`зрізМежП()`, `голос_помада.js`); самі межі й слова без читача малювач бере
   її читачами (`межіПаспорта`, `безЧитачаП`) — це слова стилістки й жінки, вони йдуть крізь точку виходу зі «своїми». */
Екран.змінити({межі: 0});
function показатиМежі(){ Екран.змінити({межі: Number(Екран.стан.межі) + 1}); }
Екран.малювач('межі', ['межі'], () => {
  const е = $('обр-межі'); if (!е) return;
  const п = ПАСПОРТ_П, сп = межіПаспорта(п), з = зрізМежП(), речення = [];
  if (з.без_моделі)
    речення.push('Стилістка не зрозуміла твоїх слів — випадок узято з плиток і чипів.');
  const нечитані = безЧитачаП(п);
  if (сп.length) речення.push('Твої межі враховано: ' + сп.join(', ') + '.');
  else if (з.почуто && !нечитані.length)
    речення.push('Твої слова передано стилістці, але твердою межею цього разу вони не стали.');
  /* ЧЕСНО ПРО СЛОВО, ЯКОГО КОД НЕ ЧИТАЄ: воно не зникає — стилістка бачить його в брифі й складає образ із ним, —
     але «враховано» про нього не кажемо, бо з пулу воно не зняло нічого. */
  if (нечитані.length)
    речення.push('Передано стилістці, але твердою межею ці слова не стали: ' + нечитані.join(', ') + '.');
  текстЖінціП(е, речення.join(' '), undefined, своїЕкрануП());
  е.style.display = речення.length ? 'block' : 'none';
});
