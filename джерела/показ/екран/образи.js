/* ── ЕКРАН: ОБРАЗИ ─────────────────────────────────────────────────────────
   Шапка й каркас екрана образів: які картки стоять у `#картки`, котра з них на екрані (пейджер), рядок випадку, рядок
   меж («що код справді застосував»), рядок «не ця» з «Повернути всі». Саму картку будує `екран/картка.js`
   (`рендерКартку`, `підвʼязатиКартку`); вердикт і логіка заміни речі ще в `картки.js`.
   СТАН ЕКРАНА:
   · `образи` — зріз показаного прогону (`зрізОбразівП()`, `картки.js`) з лічильником `подій`: логіка кличе
     `показатиОбрази()` щоразу, коли картки треба збудувати наново (збирання, відкриття з бібліотеки, приміряння).
     ОБРАЗ ЗНАЄ, ЗВІДКИ ВІН (наряд Екран-наново, дошка 15122): на кожну показану картку зріз несе руку й збирання, яке
     її дало (сід, ключ перестановки, позиція), — узяте з самої картки, де його записано в мить збирання, а не з `ЗБ`,
     який наступне збирання переписує. Жінці це не малюється; стенд читає `Екран.стан.образи.картки[поз].збирання`.
   · `образ` — котра картка на екрані (`поз`) і лічильник гортань (`подій`): гортання веде вікно догори, новий показ
     карток — ні.
   · `пейджер` — лічильник «лічбу вердиктів показати наново»: логіка кличе `показатиПейджер()` після запису вердикту.
   · `межі` — лічильник «рядок меж показати наново»: логіка кличе `показатиМежі()` після кожного запису паспорта (хід
     розмови, виклик 0 збирання, відкритий сценарій, коментар до картки) і перед показом карток. Що сказати, логіка
     каже прапорцями (`зрізМежП()`, `голос_помада.js`); самі межі й слова без читача малювач бере її читачами
     (`межіПаспорта`, `безЧитачаП`) — це слова стилістки й жінки, вони йдуть крізь точку виходу зі «своїми».
   · `не_ця`, `не_ця_рядки` — лічильники «рядок над картками» й «рядки під переліками карток»: логіка кличе
     `показатиНеЦю()` після кожної зміни набору відхилених речей (`НЕ_ЦЯ_П`), а посеред заміни речі —
     `показатиНеЦю(true)`: тоді інших карток не чіпаємо. */
