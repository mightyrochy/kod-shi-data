Екран.малювач('межі', ['межі'], () => {
  const е = $('обр-межі'); if (!е) return;
  const п = ПАСПОРТ_П, сп = межіПаспорта(п), з = зрізМежП(), речення = [];
  if (з.без_моделі)
    речення.push('Стилістка не зрозуміла твоїх слів — випадок узято з плиток і чипів.');
  const нечитані = безЧитачаП(п);
  if (сп.length) речення.push('Твої межі враховано: ' + сп.join(', ') + '.');
  else if (з.почуто && !нечитані.length)
    речення.push('Твої слова передано стилістці, але твердою межею цього разу вони не стали.');
  /* ЧЕСНО ПРО СЛОВО, ЯКОГО КОД НЕ ЧИТАЄ: воно не зникає — стилістка бачить його в брифі й складає образ із ним, —
     але «враховано» про нього не кажемо, бо з пулу воно не зняло нічого. */
  if (нечитані.length)
    речення.push('Передано стилістці, але твердою межею ці слова не стали: ' + нечитані.join(', ') + '.');
  текстЖінціП(е, речення.join(' '), undefined, своїЕкрануП());
  е.style.display = речення.length ? 'block' : 'none';
});

/* ── «не ця» ── */
function рядокНеЦяП(рука){
  const н = рука === undefined ? НЕ_ЦЯ_П.size : НЕ_ЦЯ_П.ідиРуки(рука).length;
  return н
    ? ('До заміни позначено: ' + н + '. Натисни «Зібрати ще раз» — позначених речей там не буде.') : '';
}
/* Біля позначеної речі — лише чинне відхилення для майбутнього повного збору. */
function рядокПідПереліком(єПозначена, рука){
  return єПозначена ? рядокНеЦяП(рука) : '';
}
/* ДВА МІСЦЯ, І ОБИДВА ПОТРІБНІ. Біля самого списку речей — бо там стався дотик, і саме там жінка дивиться; блок «Що
   заважає?» для цього не годиться: він `display:none`, доки вона не обрала вердикт, тобто в мить тапу по «не ця» його
   на екрані нема. Над картками — бо там стоїть «Зібрати ще раз», і там же має бути спосіб усе повернути.
   НА КАРТЦІ РЯДОК СТОЇТЬ ЛИШЕ ТАМ, ДЕ ПОЗНАЧЕНА РІЧ І Є: після нового збору її на картці вже нема, і «позначено
   речей» там, де нічого не позначено, читалось би як помилка. Сам факт при цьому нікуди не дівається — він лишається
   над картками, поки набір не порожній. */
Екран.малювач('не-ця', ['не_ця'], () => {
  const е = $('обр-не-ця'); if (!е) return;
  const н = НЕ_ЦЯ_П.size, д10 = н % 10, д100 = н % 100;
  const річ = (д10 === 1 && д100 !== 11) ? 'річ'
            : ((д10 >= 2 && д10 <= 4 && (д100 < 12 || д100 > 14)) ? 'речі' : 'речей');
  текстЖінціП($('обр-не-ця-текст'), н ? ('Ти позначила на заміну ' + н + ' ' + річ
    + ' — у наступному зборі в цих образах ' + (н === 1 ? 'її' : 'їх') + ' не буде. ') : '');
  е.style.display = н ? 'block' : 'none';
});
