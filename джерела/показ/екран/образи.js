/* Новий показ починається з першої картки й вікна не гортає: гортає лише дотик і явний вибір (`показатиОбраз`). */
function показатиОбрази(){
  Екран.змінити({образи: Object.assign({подій: Number(Екран.стан.образи.подій) + 1}, зрізОбразівП()),
                 образ: {поз: 0, подій: Number(Екран.стан.образ.подій)}});
  if (Екран.стан.образи.картки.length) завершитиДіюЯдра('показатиОбраз', 0);
}
/* Один образ на екран. Ім'я тримають стенди й логіка («готово з цією карткою» веде на наступну неоцінену). */
function показатиОбраз(n){
  const усіх = Number(Екран.стан.образи.картки.length); if (!усіх) return;
  Екран.змінити({образ: {поз: Math.max(0, Math.min(усіх - 1, n)), подій: Number(Екран.стан.образ.подій) + 1}});
  завершитиДіюЯдра('показатиОбраз', Екран.стан.образ.поз);
}
function показатиПейджер(){ Екран.змінити({пейджер: Number(Екран.стан.пейджер) + 1}); }
function показатиМежі(){ Екран.змінити({межі: Number(Екран.стан.межі) + 1}); }
function показатиНеЦю(лишеШапка){
  Екран.змінити(лишеШапка ? {не_ця: Number(Екран.стан.не_ця) + 1}
                          : {не_ця: Number(Екран.стан.не_ця) + 1, не_ця_рядки: Number(Екран.стан.не_ця_рядки) + 1});
}

