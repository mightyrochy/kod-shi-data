/* Профіль із будь-якого місця (напр., «До профілю» з уваги на сценарії або «Відповісти на три питання» з палітри):
   відкрити огляд і одразу той аркуш, у якому лежить потрібний блок. */
function відкритиПрофіль(ід){
  режим('профіль');
  if (ід) відкритиАркушПрофілю(ід);
}
/* Блоки профілю — ті самі, що на кроках знайомства; назви аркушів — `НАЗВИ_АРКУШІВ` (навігація). */
