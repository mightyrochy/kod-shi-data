/* Рамки, щаблі, поступ і оголошення — одним малювачем: оголошення повторює той самий рядок поступу. Відмова
   (лічильник зрізу виріс) і зупинене збирання оголошують рядок статусу, який стоїть у `зб-статус`. */
Екран.малювач('збирання-поступ', ['збирання'], (с, до) => {
  const з = зрізЗбиранняП();
  const відмова = !!до.збирання && Number(с.збирання.відмов) !== Number(до.збирання.відмов);
  /* питання нагоди — теж подія запуску: область оголошень каже його, а не тримає попередню відмову (15106) */
  if (до.збирання && з.статус.код === 'питання' && Number(с.збирання.статус.подій) !== Number(до.збирання.статус.подій)){
    оголоситиЗбиранняП($('зб-питання').textContent); return;
  }
  if (!з.є){ if (відмова) оголоситиЗбиранняП($('зб-статус').textContent); return; }
  const р = $('рамки');
  if (р){
    if (!р.children.length) for (let i = 0; i < 4; i++) р.appendChild(ел('div', 'рамка'));
    const мін = Number(з.етап);
    const щабель = з.готово ? 3 : (мін <= 1 ? 0 : (мін === 2 ? 1 : 2));
    р.dataset.щабель = щабель;
    const слово = з.готово ? '' : СЛОВА_СТАНУ[Math.max(0, Math.min(4, мін))];
    [...р.children].forEach(д=>{ if (д.textContent !== слово) розміткаЖінціП(д, слово ? '<span>' + слово + '</span>' : ''); });
    const ст = $('стани');
    if (ст){
      const крапки = [...ст.querySelectorAll('i')], слова = [...ст.querySelectorAll('span')];
      крапки.forEach((к, n)=>{ к.className = n < щабель ? 'було' : (n === щабель ? 'тут' : ''); });
      слова.forEach((с, n)=>{ с.className = n === щабель ? 'тут' : (n < щабель ? 'було' : ''); });
    }
    const тк = $('ткання'); if (тк){ тк.classList.toggle('тихо', !!з.готово); тк.dataset.щабель = щабель; }
  }
  /* Поступ без позиції картки: позиції рук сліпі, а рядок «варіант N: готово» чи його стадія видали б, яка картка
     з каталогом. Тому — скільки готово і стадії решти, упорядковані за написом, а не за позицією. */
  const e = $('зб-поступ');
  const поступ = [НАПИС_ОЧІКУВАННЯ_П.готово(Number(з.готових), Number(з.усього))]
    .concat(з.решта.map(ст => написСтадіїП(ст) || 'чекає…')
      .sort((а, б) => а.localeCompare(б, 'uk'))).join('\n');
  if (e){ текстЖінціП(e, поступ); if (з.підсумок) діагнозВласникаП(e, [e.textContent, з.підсумок]); }
  const напис = з.готово
    ? (з.успіх ? $('стани').querySelector('span:last-child').textContent : $('зб-статус').textContent)
    : поступ;
  оголоситиЗбиранняП(напис);
});
