/* ЗАМІНА РЕЧІ НА КАРТЦІ (перепис екрана, частина 7г).
   Логіка (`картки.js`: `замінитиРічП`, `позначитиЗамінуП`, `позначитиНеЦюП`) вузлів не торкається. Вона тримає дані:
   · набір відхилених речей сценарію `НЕ_ЦЯ_П` (ід + рука) — з нього позначка «на заміну» на кнопці, рядку й фото;
   · що про заміну видно на картці — `показЗаміниП(поз)`: `іде` (заміна в дорозі: кнопки мовчать, рядок під переліком
     схований), `нема` (ід → речення «заміни нема» біля речі), `відмова` (речення збою під переліком).
   Екран малює їх на імена `показатиЗаміну(поз)` і `показатиВідмовуЗаміни(поз)`; стан екрана — лише лічильники подій
   за позиціями (об'єкти, замінювані цілим). Речення відмови лягає в той самий вузол, що й рядок «позначено: N»
   (малювач `не-ця-рядки`), тому пишеться на подію, а не на кожне перемалювання. */
Екран.змінити({заміна: {}, відмова_заміни: {}});

/* Вигляд кнопки за станом: клас, напис і значок міняються разом — ні одне місце, що знімає чи ставить позначку,
   не пише напис сам. Слова — таблиця логіки `ЗАМІНА_П` (ті самі, що в довідці й промпті мовного шару). */
function виглядКнопкиЗаміниП(кн, позначено){
  кн.classList.toggle('вибр', !!позначено);
  кн.setAttribute('aria-pressed', позначено ? 'true' : 'false');
  розміткаЖінціП(кн, ЗАМІНА_П.значок[позначено ? 'стан' : 'дія'] + '<span>' + (позначено ? ЗАМІНА_П.стан : ЗАМІНА_П.дія) + '</span>');
}

function показатиЗаміну(поз){
  Екран.змінити({заміна: подіяПозиції(Екран.стан.заміна, поз, {})});
}
function показатиВідмовуЗаміни(поз){
  Екран.змінити({відмова_заміни: подіяПозиції(Екран.стан.відмова_заміни, поз, {})});
}

/* Котрий показ образів зараз на екрані й чи картка `поз` того показу досі перед жінкою: режим «образи», картка не
   схована, образів наново не показували. Заміна, почата на картці, живе лише доти (`замінитиРічП`). */
function котрийПоказОбразів(){ return Number(Екран.стан.образи.подій); }
function карткаПередЖінкою(поз, показ){
  return Екран.стан.режим === 'образи' && Number(Екран.стан.образ.поз) === Number(поз)
    && Number(Екран.стан.образи.подій) === показ;
}
Екран.малювач('сторож-заміни', ['режим', 'образ', 'образи'], () => скасуватиЗаміниПозаЕкраномП());

/* Картка `поз`: позначки «на заміну» (кнопка, рядок речі, фото) — з набору; кнопки мовчать і рядок під переліком
   схований, поки заміна в дорозі; «заміни нема» — біля речі, про яку це сказано. */
function малюватиЗаміну(поз){
  const вузол = $('к-' + поз); if (!вузол) return;
  const рука = рукаПозП(поз), з = показЗаміниП(поз);
  вузол.querySelectorAll('button.замін').forEach(кн => {
    const позначено = НЕ_ЦЯ_П.has(String(кн.dataset.id), рука);
    виглядКнопкиЗаміниП(кн, позначено);
    if (кн.parentElement) кн.parentElement.classList.toggle('замінити', позначено);
    кн.disabled = !!з.іде;
    const рядок = кн.parentElement && кн.parentElement.querySelector('.н');
    if (!рядок) return;
    const старий = рядок.querySelector('.заміни-нема'), речення = з.нема[String(кн.dataset.id)];
    if (старий) старий.remove();
    if (речення != null) рядок.appendChild(елЖінціП('div', 'заміни-нема', речення, 'replacement_not_found'));
  });
  вузол.querySelectorAll('.ф[data-id]').forEach(ф =>
    ф.classList.toggle('замінити', !!ф.dataset.id && НЕ_ЦЯ_П.has(String(ф.dataset.id), рука)));
  const підПереліком = вузол.querySelector('.не-ця-рядок');
  if (підПереліком) підПереліком.hidden = !!з.іде;
}
Екран.малювач('заміна', ['заміна'], (с, до) => {
  for (const поз of (до.заміна ? зПодією(с.заміна, до.заміна) : Object.keys(с.заміна))) малюватиЗаміну(поз);
});
Екран.малювач('відмова-заміни', ['відмова_заміни'], (с, до) => {
  for (const поз of зПодією(с.відмова_заміни, до.відмова_заміни)){
    const вузол = $('к-' + поз), рядок = вузол && вузол.querySelector('.не-ця-рядок');
    if (рядок) текстЖінціП(рядок, показЗаміниП(поз).відмова, 'assembly_text_failed');
  }
});
