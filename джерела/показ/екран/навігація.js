/* АРКУШ. `поставлено` — куди повернути вузол і яким був фон; це слід малювача, а не стан: стан каже лише, що відкрито. */
let поставлено = null;
function знятиАркуш(){
  const {вузол, дім, наступний, було_hidden, було_open, фон, аркуш} = поставлено; поставлено = null;
  if (дім){ if (наступний && наступний.parentNode === дім) дім.insertBefore(вузол, наступний); else дім.appendChild(вузол); }
  вузол.hidden = було_hidden; if (було_open != null && вузол.tagName === 'DETAILS') вузол.open = було_open;
  $('аркуш').hidden = true; $('аркуш-тіло').innerHTML = '';
  $('заслона').hidden = true;
  for (const [в, було] of фон){
    if (було === null) в.removeAttribute('inert'); else в.setAttribute('inert', було);
  }
  const сповіщення = $('збій-панель');
  if (сповіщення){ document.body.appendChild(сповіщення); сповіщення.removeAttribute('inert'); }
  document.documentElement.classList.remove('аркуш-відкрито');
  document.querySelectorAll('.ряд-паспорта.відкрито').forEach(р => р.classList.remove('відкрито'));
  /* Збій того, хто домальовує після аркуша, не ковтається: фокус повертається, а виняток іде далі. */
  try { if (аркуш.після) аркуш.після(); }
  finally {
    const ф = [аркуш.відкривач, аркуш.повернення && аркуш.повернення()].find(в => в && в.isConnected && в.tabIndex >= 0
      && !в.matches(':disabled') && !в.closest('[inert]') && в.getClientRects().length
      && getComputedStyle(в).visibility === 'visible');
    if (ф) ф.focus({preventScroll: true});
  }
}
function поставитиАркуш(аркуш){
  const а = $('аркуш'), т = $('аркуш-тіло'), вузол = аркуш.вузол;
  поставлено = {вузол, дім: вузол.parentNode, наступний: вузол.nextSibling, було_hidden: вузол.hidden,
                було_open: ('open' in вузол) ? вузол.open : null, фон: [], аркуш};
  т.innerHTML = ''; т.appendChild(вузол);
  вузол.hidden = false; if ('open' in вузол && вузол.tagName === 'DETAILS') вузол.open = true;
  назваЖінціП($('аркуш-назва'), НАЗВИ_АРКУШІВ[вузол.id] || '');
  $('аркуш-скасувати').hidden = !аркуш.скасувати;
  $('аркуш-готово').hidden = !аркуш.готово;
  а.hidden = false; $('заслона').hidden = false;
  document.documentElement.classList.add('аркуш-відкрито');
  /* Фон не бере клавіатуру й не читається як частина модального вікна.
     Збережений inert повертається дослівно: аркуш не вмикає чужий схований фон. */
  for (const в of document.body.children){
    if (в === а || в.id === 'заслона' || /^(SCRIPT|STYLE)$/.test(в.tagName)) continue;
    поставлено.фон.push([в, в.getAttribute('inert')]); в.setAttribute('inert', '');
  }
  const фокуси = фокусиАркуша(), заданий = аркуш.фокус && $(аркуш.фокус);
  (фокуси.includes(заданий) ? заданий : фокуси[0] || а).focus();
}
Екран.малювач('аркуш', ['аркуш'], с => {
  if (поставлено) знятиАркуш();
  if (с.аркуш) поставитиАркуш(с.аркуш);
});

