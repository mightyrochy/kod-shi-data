  const фб = $('ф-блок'), фбВАркуші = !!(с.аркуш && с.аркуш.вузол === фб);
  const фотоВправо = три && с.режим === 'профіль';
  if (!фбВАркуші) перенести(фб, фотоВправо ? $('правий-місце') : $('ф-блок-місце'));
