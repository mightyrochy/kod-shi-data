/* Клавіатура в аркуші: Escape закриває, Tab ходить колом по його полях. */
function фокусиАркуша(){
  return [...$('аркуш').querySelectorAll('button, input, select, textarea, a[href], summary, [tabindex]')]
    .filter(в => в.tabIndex >= 0 && !в.matches(':disabled') && !в.closest('[inert]')
      && в.getClientRects().length && getComputedStyle(в).visibility !== 'hidden');
}
document.addEventListener('keydown', е => {
  if (!Екран.стан.аркуш) return;
  if (е.key === 'Escape'){ е.preventDefault(); закритиАркуш(); return; }
  if (е.key !== 'Tab') return;
  const ф = фокусиАркуша(), перший = ф[0], останній = ф[ф.length - 1];
  if (!ф.length){ е.preventDefault(); $('аркуш').focus(); }
  else if (!ф.includes(document.activeElement) || (е.shiftKey ? document.activeElement === перший : document.activeElement === останній)){
    е.preventDefault(); (е.shiftKey ? останній : перший).focus();
  }
});

