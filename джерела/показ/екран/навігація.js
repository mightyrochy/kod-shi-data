  перенести($('шапка-дії'), ш ? $('бік-дії') : $('шапка-дії-місце'));
  перенести(ніг, ш ? $('колонка') : document.body);
  const карткаВправо = три && с.режим === 'сценарій';
  перенести($('сц-увага'), карткаВправо ? $('правий-місце') : $('сц-увага-місце'));
