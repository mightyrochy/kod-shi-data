/* Вхід у режим і на крок — події, а не лише значення: повторний вхід наново наповнює екран (`вхід`, `вхід_кроку`). */
function режим(р){
  if (Екран.стан.аркуш) Екран.змінити({аркуш: null});
  Екран.змінити(Object.assign({режим: р, вхід: Екран.стан.вхід + 1}, ширинаЕкрана()));
  if (р !== 'сценарій') розмоваПозаСценарієм();
  наповнитиСтаріЕкрани(true);
  if (р === 'старт') завершитиДіюЯдра('екран', Екран.стан.крок);
  завершитиДіюЯдра('режим', р);
}
function екран(i){
  Екран.змінити({крок: Math.max(0, Math.min(КРОКИ_ЗНАЙОМСТВА.length - 1, i)), вхід_кроку: Екран.стан.вхід_кроку + 1});
  наповнитиСтаріЕкрани(false);
  завершитиДіюЯдра('екран', Екран.стан.крок);
}
