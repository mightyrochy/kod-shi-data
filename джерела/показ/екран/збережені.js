/* ── ЕКРАН: ЗБЕРЕЖЕНІ СЦЕНАРІЇ ─────────────────────────────────────────────
   Назва відкритого сценарію й чи його збережено (шапка картки), форма збереження, екран «Збережені» і рейка
   збережених у бічній колонці.
   СТАН ЕКРАНА: `збережені` — зріз логіки (`зрізЗбереженихП()`: який сценарій відкрито — ід, час, «змінено», чи
   названо; номер читання переліку й чи він прочитався); `збереження` — підсумок збереження з форми {`код`: '' |
   'збережено' | 'збій', `подій` — лічильник збережень}; `видалення` — ід рядка «Збережених», на якому «видалити» вже
   торкнуто раз (суто екранне).
   ЛОГІКА КАЖЕ ПРО ЗМІНУ ІМЕНЕМ `показатиЗбережені()`: відкритий сценарій (`СЦ`) чи перелік збережених
   (`оновитиСценарії`, `показ/бібліотека.js`) змінились. Сховища екран не читає: записи — з моделі логіки
   (`ЗБЕРЕЖЕНІ_П`, голим іменем — так походження назви видно приладу). Назва — її слова: у стані її нема, малювач бере `СЦ` і записи там, де їх видно цілими, і кладе
   на екран крізь `назваСценаріюП`; у форму назва йде її ж словами, а з форми дія бере її рядком у мить дотику. */
Екран.змінити({збереження: {код: '', подій: 0}, видалення: null});
function показатиЗбережені(){ Екран.оновити({збережені: зрізЗбереженихП()}); }
/* Вхід на «Збережені» (кличе `режим()`): перелік читається наново, «видалити» знову чекає першого дотику. */
function збереженіВідкрито(){ Екран.змінити({видалення: null}); оновитиСценарії(); }

/* ── ФОРМА ЗБЕРЕЖЕННЯ ── аркуш. Ім'я лишено: ним водять стенди, і логіка закриває ним форму на новому й відкритому
   сценарії. */
function показатиФормуЗбереження(показ){
  const ф = $('сц-збер-форма'); if (!ф) return;
  const а = Екран.стан.аркуш;
  if (!показ){ if (а && а.вузол === ф) закритиАркуш(); return; }
  їїСловаП($('сц-назва-поле'), СЦ.назва || '', 'value');
  Екран.змінити({збереження: {код: '', подій: Number(Екран.стан.збереження.подій)}});
  показатиЗбережені();
  відкритиАркуш(ф, {готово: false, фокус: 'сц-назва-поле'});
}
/* «Зберегти» / «Оновити»: назва — рядок з її поля в мить дотику; записалось — форма закривається. */
async function зберегтиЗФорми(якНовий){
  const вийшло = await зберегтиЗФормиП($('сц-назва-поле').value, якНовий);
  if (вийшло) показатиФормуЗбереження(false);
  Екран.змінити({збереження: {код: вийшло ? 'збережено' : 'збій', подій: Number(Екран.стан.збереження.подій) + (вийшло ? 1 : 0)}});
}

/* ── ДІЇ ── */
Екран.дія('збереження-відкрити', () => показатиФормуЗбереження(true));
Екран.дія('збереження-скасувати', () => показатиФормуЗбереження(false));
Екран.дія('збереження-новим', () => зберегтиЗФорми(true));
Екран.дія('збереження-оновити', () => зберегтиЗФорми(false));
Екран.дія('сценарій-новий', () => новийСценарій());
Екран.дія('сценарій-образу', () => відкритиСценарійОбразуП());
Екран.дія('збережений-відкрити', ід => відкритиСценарій(ід));
/* видалення — двома дотиками, без системного вікна: перший називає, другий робить */
Екран.дія('збережений-видалити', async ід => {
  if (Екран.стан.видалення !== ід){ Екран.змінити({видалення: ід}); return; }
  Екран.змінити({видалення: null});
  await видалитиСценарій(ід);
});
Екран.слухати({'сц-зберегти': 'збереження-відкрити', 'сц-збер-скасувати': 'збереження-скасувати',
  'сц-збер-новий': 'збереження-новим', 'сц-збер-оновити': 'збереження-оновити',
  'сц-новий': 'сценарій-новий', 'сцн-новий': 'сценарій-новий', 'обр-сценарій': 'сценарій-образу'});

/* ── НАЗВА ВІДКРИТОГО СЦЕНАРІЮ ── шапка картки й кнопки форми; назва — її ввід чи підпис без назви з датою */
Екран.малювач('назва-сценарію', ['збережені'], () => {
  const н = $('сц-назва'), с = $('сц-назва-стан'); if (!н || !с) return;
  назваСценаріюП(н, СЦ.назва, СЦ.час);
  с.textContent = СЦ.ід ? (СЦ.змінено ? 'збережений · є незбережені зміни' : 'збережений')
                        : (СЦ.змінено ? 'не збережений' : '');
  const о = $('сц-збер-оновити');
  if (о){ о.style.display = СЦ.ід ? '' : 'none'; текстЖінціП(о, підписЗНазвоюП(['Оновити «', {назва: СЦ.назва || підписБезНазвиП(СЦ.час)}, '»'])); }
  const нв = $('сц-збер-новий'); if (нв) нв.textContent = СЦ.ід ? 'Зберегти як новий' : 'Зберегти';
});
/* Підсумок збереження з форми: збій — шаблоном під полем назви (слід лишила логіка), збережено — рядком статусу. */
Екран.малювач('підсумок-збереження', ['збереження'], (с, до) => {
  const ст = $('сц-збер-стан'); if (!ст) return;
  ст.textContent = с.збереження.код === 'збій' ? ШАБЛОНИ_ЗБОЮ_П.not_saved : '';
  if (с.збереження.код === 'збережено' && до.збереження && до.збереження.подій !== с.збереження.подій)
    текстЖінціП($('зб-статус'), підписЗНазвоюП(['Сценарій збережено як «', {назва: СЦ.назва || підписБезНазвиП(СЦ.час)}, '».']));
});

/* ── РЯДОК ЗБЕРЕЖЕНОГО ── кнопка «відкрити»: назва, про що й дата. Один на «Збережені» й картку переліку в розмові
   (`карткаІнструментаП`): дотик — та сама дія `збережений-відкрити`. Назву (`назва` — вузол <b>) малює викликач над
   записом (`назваСценаріюП`: її ввід чи підпис без назви). */
function кнопкаСценаріюП(с, назва){
  const кн = ел('button', 'сцн-відкрити' + (с.ід === СЦ.ід ? ' тут' : '')); кн.type = 'button'; кн.dataset.ключ = с.ід;
  кн.appendChild(назва);
  const опис = [проЩоСценарійП(с), String(с.час || '').slice(0, 10)].filter(Boolean);
  const частини = опис.flatMap((ч, і) => [...(і ? [' · '] : []), {назва: ч}]);
  if (с.ід === СЦ.ід) частини.push(...(частини.length ? [' · '] : []), 'відкрито зараз');
  кн.appendChild(елЖінціП('small', null, підписЗНазвоюП(частини)));
  кн.onclick = () => Екран.відЖінки('збережений-відкрити', с.ід);
  return кн;
}
const написВидалити = (г, названо) => { г.textContent = названо ? 'точно видалити?' : 'видалити'; };

/* ── «ЗБЕРЕЖЕНІ» ── перелік з моделі логіки; до першого читання екран порожній */
Екран.малювач('перелік-збережених', ['збережені'], с => {
  const сп = $('сцн-список'), ст = $('сцн-стан'); if (!сп || !ст) return;
  сп.innerHTML = ''; ст.textContent = '';
  if (!с.збережені.читань) return;
  if (с.збережені.збій){ ст.textContent = ШАБЛОНИ_ЗБОЮ_П.scenarios_unreadable; return; }
  if (!ЗБЕРЕЖЕНІ_П.length){
    ст.textContent = 'Ще порожньо. Опиши випадок на головному екрані й натисни «Зберегти» — він зʼявиться тут.';
    return;
  }
  ЗБЕРЕЖЕНІ_П.forEach(з=>{
    const к = ел('div', 'сцн');
    const н = ел('b'); назваСценаріюП(н, з.назва, з.час);
    const г = ел('button', 'текст сцн-геть'); г.type = 'button'; г.dataset.ключ = з.ід;
    написВидалити(г, з.ід === с.видалення);
    г.onclick = () => Екран.відЖінки('збережений-видалити', з.ід);
    к.appendChild(кнопкаСценаріюП(з, н)); к.appendChild(г); сп.appendChild(к);
  });
});
/* Перший дотик «видалити» лише називає: напис міняється на місці, рядки не перебудовуються. */
Екран.малювач('видалення-назване', ['видалення'], с => {
  document.querySelectorAll('#сцн-список .сцн-геть').forEach(г => написВидалити(г, г.dataset.ключ === с.видалення));
});

