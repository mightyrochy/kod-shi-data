/* ── ПЕРЕЛІК ОБРАЗІВ ── плитка: мініатюра, «N образ», дата й випадок, останній вердикт. */
function плиткаБібліотеки(пл, н){
  const р = ел('button', 'біб-образ'); р.type = 'button'; р.id = 'біб-образ-' + н;
  /* Клас — ЛИШЕ на приміряному кадрі: фото речі лишається таким самим
     вузлом, яким було (`.річ` тут не можна — це клас рядка речі в картці,
     і на `<img>` він приносить сітку й лінію згори). */
  /* ФОТО РЕЧІ ЙДЕ БЕЗ `src` — його ставить ланцюг кадрів нижче (Ф-143): інакше
     та сама адреса запитувалась би двічі. Приміряний кадр — як був, одним `src`:
     ряду кадрів у нього нема, це один намальований знімок. */
  const мін = (пл.кадр || пл.річ)
    ? (пл.кадр ? '<img class="приміряно" src="' + пл.кадр.replace(/"/g, '&quot;') + '" alt="">'
               : '<img alt="">')
    : '<i class="арка"></i>';
  /* каркас — розмітка без слів; слова плитки (дата й випадок — дані, вердикт) лягають крізь точку виходу */
  розміткаЖінціП(р, '<span class="біб-мін">' + мін + '</span><span class="біб-текст"><b></b><small></small><em></em></span>');
  текстЖінціП(р.querySelector('b'), (ЧИСЛА[пл.поз] || (пл.поз + 1)) + ' образ');
  текстЖінціП(р.querySelector('small'), [пл.дата, пл.решта].filter(Boolean).join(' \u00b7 '), undefined, своїЕкрануП(пл.картка));
  текстЖінціП(р.querySelector('em'), пл.вердикт ? (вердиктЗаписуП(пл.вердикт) + (пл.записів > 1 ? ' \u00b7 ' + пл.записів + ' записи' : '')) : 'ще без вибору');
  /* ── БИТА МІНІАТЮРА ПАДАЄ НА ТОЙ САМИЙ СИЛУЕТ (доповнення Л-8) ───────
     Фото крамниці не відкрилось (мережі нема, адреса протухла, крамниця
     віддала 404) — і плитка лишалась зі значком битої картинки браузера,
     різним на кожному телефоні й чужим цьому екрану. Картка на такий
     випадок запасний стан уже мала (`полотно`: `к.картинка = null`),
     плитка — ні. Тепер бите фото заміщається тим самим `<i class="арка">`,
     що вже стоїть в образу без фото: жодного нового тексту, розкладка
     плитки та сама (аудит/ПРОДУКТ.md п.7) — лише інший вміст того ж віконця.
     Обробник ставимо ПІСЛЯ `innerHTML`, і цього досить: `error` браузер
     кидає окремим завданням, не синхронно з розбором розмітки. */
  /* ── ПЛИТКА ЙДЕ ТИМ САМИМ РЯДОМ КАДРІВ, ЩО Й КАРТКА (Ф-143, 27.09.2026) ──
     Знахідка Т-3 (`аудит/тести/2026-09-27_т3_ручний_прохід.md`): у «Всіх
     образах» мініатюри рук 1–2 стояли ПОРОЖНІ, а в консолі — `404` і
     `ERR_TOO_MANY_RETRIES`; Т-3 назвала це «той самий клас, що рядок 143».
     Так і було: картка на мертвому кадрі йде на наступний кадр речі, а
     плитка знала РІВНО ОДНУ адресу (`ф.фото`) і на помилці одразу падала в
     силует — тобто показувала «фото нема» там, де в речі є живі знімки. А
     коли хост мовчав, не було й помилки: лишалась порожня рамка, яку Т-3 і
     зняла. Тепер плитка бере той самий `підставитиКадр`: увесь ряд `фото_усі`,
     друге коло проти обриву й годинник проти мовчання. Силует лишається
     кінцем ряду, а не першою невдачею. */
  const мінІ = р.querySelector('.біб-мін img');
  const вСилует = () => { const а = document.createElement('i'); а.className = 'арка'; мінІ.replaceWith(а); };
  if (мінІ && пл.кадр) мінІ.onerror = вСилует;
  else if (мінІ) підставитиКадр(мінІ, пл.річ, вСилует);
  return р;
}
