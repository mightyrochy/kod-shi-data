/* ── ФАЙЛ ── офлайн, без сервера: Blob + `<a download>`. */
function віддатиФайл(імʼя, вміст, тип){
  const урл = URL.createObjectURL(new Blob([вміст], {type: тип}));
  const а = document.createElement('a');
  а.href = урл; а.download = імʼя; а.rel = 'noopener'; а.style.display = 'none';
  document.body.appendChild(а); а.click();
  /* Відпускаємо не одразу: на телефоні завантаження стартує після кліку, і
     відкликаний у тому ж такті урл лишив би порожній файл. */
  setTimeout(()=>{ URL.revokeObjectURL(урл); а.remove(); }, 4000);
}
