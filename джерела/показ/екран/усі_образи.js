/* ── ВИБІР ВИВАНТАЖЕННЯ: ДЕНЬ → ПРОГІН → ОБРАЗ ── прапорець образу несе номер запису в моделі (`жв-о-<н>`); прапорці
   дня й прогону свого стану не мають — їх малює `малюватиПозначкиВибору` з образів групи. */
function рядокВивантажень(з){
  const в = (з || {}).вивантажено || [];
  return в.length ? ('вже вивантажено ' + в.length + '\u00d7, останнє '
                     + String(в[в.length-1]).slice(0,16).replace('T',' '))
                  : 'ще не вивантажено';
}
