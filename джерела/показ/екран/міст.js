/* ── ЕКРАН: МІСТ І НОВА ЗБІРКА ─────────────────────────────────────────────
   Те, що жінка бачить від моста й збірки, а не від режиму: смужка «Є новіша версія Люстерка» й рядок стану, поки
   вперше тягнеться середовище розрахунків (`пал-стан`).
   СТАН ЕКРАНА: `нова_збірка` — прапорець «є новіша»: логіка прочитала штамп (`перевіритиНовішуЗбірку()`,
   `воркер_міст.js`) і кличе `показатиНовуЗбірку()`; `підйом_мосту` — зріз логіки (`зрізПідйомуМостуП()`): код кроку,
   секунди, файли, байти й лічильник подій; логіка кличе `показатиПідйомМосту()` після кожного запису. */
Екран.змінити({нова_збірка: false, підйом_мосту: зрізПідйомуМостуП()});
function показатиНовуЗбірку(){ Екран.змінити({нова_збірка: true}); }
function показатиПідйомМосту(){ Екран.оновити({підйом_мосту: зрізПідйомуМостуП()}); }

/* ── НОВА ЗБІРКА ── Перевірку просить екран: при відкритті й коли вкладка знову видима. Смужка з'являється, коли
   новіша збірка є Й екран уже виконує дотики (`вхід`): до першого входу в режим «Оновити» нічого б не зробила. */
Екран.малювач('нова-збірка', ['нова_збірка', 'вхід'], с => {
  const е = $('нова-версія'); if (е) е.hidden = !(с.нова_збірка && Number(с.вхід) > 0);
});
Екран.дія('оновити-збірку', () => перейтиНаНовішуЗбіркуП());
Екран.слухати({'нова-версія-кн': 'оновити-збірку'});
перевіритиНовішуЗбірку();
document.addEventListener('visibilitychange', () => {
  if (document.visibilityState === 'visible') перевіритиНовішуЗбірку();
});

/* ── ПІДЙОМ СЕРЕДОВИЩА ── рядок стану палітри — на подію підйому (`подій` виріс), а не на кожну зміну зрізу: у той
   самий рядок пише й палітра (`палітра.js`), і стоїть останнє сказане. Числа — зі свіжого зрізу логіки. */
const НАПИСИ_ПІДЙОМУ_МОСТУ = {
  початок: 'Готуємо палітру під твій колорит — перший раз це до хвилини.',
  мить: 'Ще мить…'};
Екран.малювач('підйом-мосту', ['підйом_мосту'], (с, до) => {
  if (!до.підйом_мосту || Number(с.підйом_мосту.подій) === Number(до.підйом_мосту.подій)) return;
  const ст = $('пал-стан'), з = зрізПідйомуМостуП(); if (!ст) return;
  if (з.код === 'тягне'){
    текстЖінціП(ст, 'Готуємо палітру під твій колорит — ' + Number(з.с) + ' с, завантажено '
      + Number(з.файлів) + ' файлів' + (Number(з.байтів) ? ' (' + (Number(з.байтів)/1048576).toFixed(1) + ' МБ)' : '')
      + '. Перший раз тягне ≈15 МБ середовища — на повільній мережі це кілька хвилин.'
      + (Number(з.с) > 300 ? ' Якщо число файлів не росте — перезавантаж сторінку.' : ''));
    return;
  }
  ст.textContent = НАПИСИ_ПІДЙОМУ_МОСТУ[з.код] || '';
});
