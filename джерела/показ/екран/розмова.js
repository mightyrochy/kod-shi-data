/* ── ШВИДКІ ВІДПОВІДІ ── паспорт каже, чого стилістка ще не знає (`невідомо`), а довідник дає слова. */
const ШВИДКІ_ВІДПОВІДІ = {
  'дрес_код': ()=>(ДОВІДНИК.коди||[]).filter(о=>о.плитка).map(о=>о.підпис.toLowerCase()),
  'місце':    ()=>(ДОВІДНИК.місця||[]).filter(о=>о.плитка).map(о=>о.підпис.toLowerCase()),
  'нагода':   ()=>(ДОВІДНИК.нагоди||[]).filter(о=>о.плитка).map(о=>о.підпис.toLowerCase()),
  'опади':    ()=>['без опадів', 'дощ', 'сніг'],
  'пора':     ()=>Object.values(ПОРА_СЛОВОМ_П)};
Екран.малювач('швидкі-відповіді', ['панель'], с => {
  const к = $('сц-швидкі');
  к.innerHTML = '';
  if (с.режим !== 'сценарій' || !ПАСПОРТ_П || !ЧАТ_П.length || ЧАТ_П[ЧАТ_П.length - 1].хто !== 'ші') return;
  const поле = (ПАСПОРТ_П.невідомо || []).find(п=>ШВИДКІ_ВІДПОВІДІ[п]);
  if (!поле) return;
  const слова = ШВИДКІ_ВІДПОВІДІ[поле]().filter(Boolean).slice(0, 7);
  if (!слова.length) return;
  слова.concat(['на твій розсуд']).forEach(т=>{
    const ч = елЖінціП('span', 'чип', т, 'chat_choice_failed', своїЕкрануП()); ч.setAttribute('role', 'button'); ч.tabIndex = 0;
    ч.onclick = () => Екран.відЖінки('швидка-відповідь', т);
    ч.onkeydown = e=>{ if (e.key === 'Enter' || e.key === ' '){ e.preventDefault(); ч.click(); } };
    к.appendChild(ч);
  });
});

