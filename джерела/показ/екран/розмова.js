/* ── МІСЦЕ СТРІЧКИ Й ПОЛЯ ──
   Стрічка розмови ОДНА, а місць два: на сценарії вона стоїть в екрані (там розмова — головна річ), деінде — у
   панелі, де її можна згорнути. Поле теж одне: на порожньому сценарії воно живе в аркуші листа посеред екрана,
   деінде — в панелі. Переносимо ВУЗОЛ, а не тримаємо дві копії: текст, фокус і обробники лишаються, а дві копії
   розійшлися б на першій правці. Рядок голосу їде ЗА полем тим самим переносом: інакше «Слухаю…» лишалось би в
   панелі, поки поле стоїть в аркуші листа, і жінка читала б його не там. */
Екран.малювач('місце-розмови', ['панель'], с => {
  const стрічка = $('чат-стрічка'), ввід = $('чат-ввід'), голос = $('чат-голос'), лист = листРозмови(с);
  const дім = с.режим === 'сценарій' ? $('сц-розмова') : $('ші-стрічка');
  if (стрічка.parentNode !== дім) дім.appendChild(стрічка);
  const місце = лист ? $('сц-лист-місце') : $('ші-поле-місце');
  if (ввід.parentNode !== місце) місце.appendChild(ввід);
  if (голос.previousElementSibling !== ввід) місце.insertBefore(голос, ввід.nextSibling);
  $('сц-лист').hidden = !лист;
  /* заголовок-питання потрібен лише до першого слова */
  $('сц-вступ').style.display = лист ? '' : 'none';
});

