/* ── ЕКРАН: РОЗМОВА ────────────────────────────────────────────────────────
   Панель розмови ціла: стрічка реплік, поле з вкладеними фото речей, пілюля, приклади, швидкі відповіді, рядок
   стану. Розмова одна на весь показ (`показ/випадок.js`, «РОЗМОВА — ОДНА НА ВЕСЬ ПОКАЗ»): на сценарії стрічка стоїть
   в екрані, а поле розгорнуте завжди; деінде поле згорнуте в пілюлю з останньою відповіддю.
   СТАН ЕКРАНА: `розмова` — зріз ходу (`зрізРозмовиП()`: код напису, «іде», «вичерпано», лічильники «репліку взято»
   й «відповідь є»); `панель` — лічильник «панель показати наново» (вона читає стрічку `ЧАТ_П`, паспорт, вкладені
   фото й прапорець `рукою` сценарію); `розгорнуто` — поза сценарієм стрічку й поле розгорнуто з пілюлі.
   ЛОГІКА КАЖЕ ПРО ЗМІНУ ІМЕНАМИ: `показатиРозмову()` — репліки, вкладення, хід чи напис змінились (панель читає й
   картка сценарію, тож вона показується тим самим іменем); `згорнутиРозмову()` — новий чи відкритий сценарій.
   Вузлів панелі логіка не чіпає: її слова дія бере з її поля в мить дотику, файли фото дає логіці списком. */
