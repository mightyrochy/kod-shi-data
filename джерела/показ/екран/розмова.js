/* ── ЕКРАН: РОЗМОВА ────────────────────────────────────────────────────────
   Ввід розмови й рядок стану під ним. Логіка ходу (`показ/паспорт.js`) вузлів панелі не чіпає: що сказати — код
   напису в її моделі, чи йде хід і чи вичерпано повідомлення — прапорці зрізу `зрізРозмовиП()`, «репліку взято» й
   «хід дійшов кінця» — лічильники. Про зміну логіка каже одним іменем — `показатиРозмову()`; слова складає малювач тут.
   ПЕРЕХІДНЕ (до частини 5в): решту панелі (стрічка, пілюля, вкладення, приклади, підказка поля) ще малює старе
   `малюватиЧатП()` у `випадок.js`: воно кличе `показатиРозмову()`, а малювач «репліку взято» кличе його. */
function показатиРозмову(){ Екран.оновити({розмова: зрізРозмовиП()}); }

/* ── ДІЇ ──
   Надіслати: її слова дія бере з її поля в мить дотику й віддає логіці рядком (`слатиРеплікуП`); поле спорожнює
   малювач, коли логіка репліку взяла. Ім'я `слатиЧатП` лишено: ним водять стенди й шлють швидкі відповіді. */
function слатиЧатП(){ return слатиРеплікуП($('чат-поле').value); }
Екран.дія('розмова-слати', () => слатиЧатП());
/* Enter шле, Shift+Enter лишає новий рядок: поле багаторядкове, бо жінка пише реченнями, а не запитами. */
Екран.дія('розмова-клавіша', подія => {
  if (подія.key === 'Enter' && !подія.shiftKey){ подія.preventDefault(); слатиЧатП(); }
});
Екран.слухати({'чат-слати': 'розмова-слати', 'чат-поле': ['keydown', 'розмова-клавіша']});

/* ── РЕПЛІКУ ВЗЯТО ──
   Її слова вже в розмові: поле порожнє, вкладені фото пішли з реплікою, панель розгорнута — вона бачить свою репліку. */
Екран.малювач('репліку-взято', ['розмова'], (с, до) => {
  if (Number((до.розмова || {}).прийнято || 0) === Number(с.розмова.прийнято)) return;
  const поле = $('чат-поле');
  малюватиВкладенняП();
  поле.value = ''; ростиПоле(поле);
  ШІ_РОЗГОРНУТО = true; малюватиЧатП();
});

/* ── ВВІД ──
   Закритий, поки хід іде і коли повідомлення вичерпано; чому — каже рядок стану. Голос, на відміну від фото, є на
   всіх екранах, і мікрофон закривається лише разом із полем, коли писати вже нікуди: це не мертва кнопка (п.9),
   а закритий увесь ввід. */
Екран.малювач('ввід-розмови', ['розмова'], с => {
  const закрито = !!(с.розмова.зайнято || с.розмова.вичерпано);
  $('чат-поле').disabled = закрито; $('чат-слати').disabled = закрито; $('чат-фото-вхід').disabled = закрито;
  $('чат-мікрофон').disabled = !!с.розмова.вичерпано;
});

/* ── РЯДОК СТАНУ ── один рядок під полем (`чат-стан`); що в ньому — код напису логіки */
const НАПИСИ_РОЗМОВИ = {
  думаю: 'Думаю…',
  без_моста: 'Нема токена доступу — стилістка мовчить. Відкрий Люстерко з посилання, '
    + 'яке дав власник. Сценарій поки що можна зібрати плитками.',
  оцінка_триває: 'Стилістка ще оцінює образ — перемкни профіль, коли вона закінчить.',
  відповідь_триває: 'Стилістка ще відповідає — перемкни профіль, коли вона закінчить.',
  /* НЕ ЗРОЗУМІЛА — КАЖЕТЬСЯ ВГОЛОС, А НЕ ЛИШЕ В СЛУЖБОВОМУ (Т-09): паспорт із плиток виглядає на екрані так само,
     як паспорт зі слів. */
  не_розібрала: 'Твоїх слів я цього разу не розібрала — випадок узято з плиток і чипів. Поправ їх рукою.',
  поправити: 'Скажи, що не так, — я перепишу паспорт.',
  вичерпано: 'Повідомлення вичерпано — поправ плитки й списки нижче.'
};
Екран.малювач('стан-розмови', ['розмова'], с => {
  const код = с.розмова.напис, ст = $('чат-стан');
  if (код === 'збій_фото') ст.textContent = ШАБЛОНИ_ЗБОЮ_П.photo_unreadable;
  else ст.textContent = НАПИСИ_РОЗМОВИ[код] || '';
});

/* ── ВІДПОВІДЬ Є ── на сценарії стрічка росте вниз: гортаємо до відповіді */
Екран.малювач('до-відповіді', ['розмова'], (с, до) => {
  if (Number((до.розмова || {}).відповідей || 0) === Number(с.розмова.відповідей)) return;
  if (с.режим === 'сценарій') window.scrollTo(0, document.documentElement.scrollHeight);
});
