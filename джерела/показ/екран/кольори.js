/* ── ПЛАШКИ ──
   Кожна риса — свій ряд з усіма точками, обідок райдужки названо. Hex не показується: людина судить квадратик. */
const РИСИ_КОЛЬОРУ = [['Шкіра', 'шкіра'], ['Волосся', 'волосся'], ['Очі', 'очі'], ['Обідок райдужки', 'кільце']];
Екран.малювач('свотчі', ['колір'], () => {
  const колір = зрізПрофіляП().колір, к = $('кол-свотчі'); к.innerHTML = '';
  for (const [назва, риса] of РИСИ_КОЛЬОРУ){
    const точки = (риса === 'шкіра' || риса === 'волосся') && (колір.точки || {})[риса]
      || (колір[риса] ? [колір[риса]] : []);
    if (!точки.length) continue;
    const г = ел('div', 'св-група');
    г.appendChild(елЖінціП('div', 'св-назва', назва + (точки.length > 1 ? ' — ' + точки.length + ' тони' : '')));
    const р = ел('div', 'св-ряд');
    точки.forEach(hex => {
      const д = ел('div', 'св'); const i = ел('i'); i.style.background = hex;
      д.appendChild(i); р.appendChild(д);
    });
    г.appendChild(р); к.appendChild(г);
  }
});

/* ── РЯДОК СТАНУ ЧИТАННЯ ──
   Рядок один (`кол-стан`) і стоїть під рядом кнопки, яку натиснули (живий прогін 13.11, вада 4). */
const КНОПКИ_ЧИТАННЯ_КОЛЬОРІВ = {зчитати: 'кол-зчитати', повтор: 'кол-повтор', читати: 'кол-читати', копія: 'кол-копія'};
const НАПИСИ_ЧИТАННЯ_КОЛЬОРІВ = {
  нема_портрета: 'Спершу додай портрет — він вище на цьому ж екрані.',
  нема_токена: 'Нема токена доступу. Відкрий Люстерко з посилання, яке дав власник (…/kod-shi-data/#токен), або скористайся іншим шляхом нижче.',
  дивиться: 'Стилістка дивиться на портрет…',
  дивиться_ще: 'Стилістка дивиться ще раз…',
  відмова: 'Стилістка відмовилась читати це фото.',
  скопійовано: 'Запит скопійовано.',
  виділи: 'Виділи текст запиту руками.'
};
const точокКольору = n => n === 1 ? 'точка' : (n < 5 ? 'точки' : 'точок');
const тонівКольору = n => n === 1 ? 'тон' : (n < 5 ? 'тони' : 'тонів');
function написЧитанняКольорів(ст, н){
  if (!н){ ст.textContent = ''; return; }
  if (н.код === 'збій_читання'){ ст.textContent = ШАБЛОНИ_ЗБОЮ_П.colors_failed; return; }
  if (н.код === 'збій_фото'){ ст.textContent = ШАБЛОНИ_ЗБОЮ_П.photo_unreadable; return; }
  if (н.код === 'виміряно'){ текстЖінціП(ст, 'Кольори виміряно з фото: шкіра, волосся й очі.'); return; }
  if (н.код === 'брак'){
    const брак = [!Number(н.шкіри) && 'шкіри', !Number(н.волосся) && 'волосся', !н.очі && 'очей'].filter(Boolean);
    текстЖінціП(ст, 'У відповіді немає: ' + (брак.length ? брак.join(', ') : 'оцінки фото')
      + '. Встав відповідь чату цілком, як є.');
    return;
  }
  if (н.код === 'прочитано'){
    const шкіри = Number(н.шкіри), волосся = Number(н.волосся);
    const прочитано = 'Прочитано: ' + шкіри + ' ' + точокКольору(шкіри) + ' шкіри, ' + волосся + ' ' + тонівКольору(волосся)
      + (н.обідок ? ', обідок райдужки' : '') + '.'
      + (н.ручний ? ' Кольори застосовано — плашки вгорі, у «Твої кольори».' : '');
    /* ворота виміру не пройдено: який портрет надіслати — речення мовної моделі, без нього — сталий напис */
    if (н.що_надіслати) текстЖінціП(ст, прочитано + ' ' + (н.шар || НАПИС_БЕЗ_ШАРУ_П.portrait_unmeasured),
                                    'portrait_unmeasured', своїЕкрануП());
    else текстЖінціП(ст, прочитано);
    return;
  }
  /* відмова: причина — кодом, речення — мовна модель (п.12); без її речення — лише сталий напис */
  if (н.код === 'відмова' && н.шар){
    текстЖінціП(ст, НАПИСИ_ЧИТАННЯ_КОЛЬОРІВ.відмова + ' ' + н.шар, 'portrait_unreadable', своїЕкрануП());
    return;
  }
  ст.textContent = НАПИСИ_ЧИТАННЯ_КОЛЬОРІВ[н.код] || '';
}
Екран.малювач('читання-кольорів', ['читання_кольорів'], (с, до) => {
  const ч = зрізЧитанняКольорівП(), ст = $('кол-стан');
  const кнопка = $(КНОПКИ_ЧИТАННЯ_КОЛЬОРІВ[ч.біля]), ряд = кнопка && кнопка.closest('.ряд');
  if (ряд && ряд.nextElementSibling !== ст) ряд.after(ст);
  $('кол-зчитати').disabled = !!ч.читає;
  $('кол-повтор').hidden = !ч.повтор; $('кол-повтор').disabled = !!ч.повторює;
  /* читання скинуто (інший профіль, інше фото, нове читання) — вставлена відповідь чату теж чужа */
  if (до.читання_кольорів && Number(до.читання_кольорів.скидань) !== Number(ч.скидань)) $('кол-відповідь').value = '';
  написЧитанняКольорів(ст, ч.напис);
});
