/* ── ЕКРАН: ЯДРО ───────────────────────────────────────────────────────────
   Шар екрана — усе, що жінка бачить і чого торкається, — живе в `показ/екран/` і тримається трьох речей:
   1. СТАН ЕКРАНА МАЄ ОДНОГО ПИСАЧА. Що зараз на екрані (режим, крок, аркуш, лічильники, написи стану) лежить в одному
      об'єкті; пише в нього лише `Екран.змінити(латка)`. Зріз (значення ключа) замінюють цілим, а не правлять усередині.
   2. ВІД ДІЇ ДО ВИДИМОГО — ОДИН ШЛЯХ: подія DOM → названа дія (`Екран.дія`) → функція логіки →
      `Екран.змінити` → малювачі (`Екран.малювач`) → DOM. Малювач — функція стану: усе, що показує той самий ключ
      (лічильник, напис, кнопка), малюється з нього, а не з копії в іншому місці.
   3. МЕЖА З ЛОГІКОЮ — ІМЕНА. Екран кличе функції логіки (`показ/*.js`) прямо, іменем: так їх бачать стенди й
      прилади коренів, що читають шлях від обробника до запису. Логіка DOM не торкається й екрана не знає; правил
      продукту й промптів у коді екрана нема. Перелік межі й обходи лічить `проби/екран_межа.py`. */
const Екран = (() => {
  const стан = Object.create(null);
  const малювачі = [];
  const дії = Object.create(null);
  let малюється = false, було = Object.create(null);
  const чекають = new Set();
  const простий = з => з && typeof з === 'object' && [Object.prototype, Array.prototype].includes(Object.getPrototypeOf(з));

  /* ЄДИНИЙ ПИСАЧ. Малювачі біжать одразу й у порядку реєстрації; зміна зсередини малювача домальовується наступним
     колом того самого виклику, тож після `змінити` DOM уже відповідає стану. */
  function змінити(латка){
    for (const к of Object.keys(латка)){
      if (стан[к] === латка[к]) continue;
      if (!(к in було)) було[к] = стан[к];
      стан[к] = простий(латка[к]) ? Object.freeze(латка[к]) : латка[к];
      чекають.add(к);
    }
    if (малюється) return;
    малюється = true;
    try {
      for (let коло = 0; чекають.size; коло++){
        if (коло > 20) throw new Error('екран: малювачі міняють стан по колу: ' + [...чекають].join(', '));
        const ключі = new Set(чекають), до = було;
        чекають.clear(); було = Object.create(null);
        for (const м of малювачі) if (м.ключі.some(к => ключі.has(к))) м.ф(читач, до);
      }
    } finally { малюється = false; чекають.clear(); було = Object.create(null); }
  }
  const читач = new Proxy(стан, {
    set(){ throw new Error('екран: стан пише лише Екран.змінити'); },
    defineProperty(){ throw new Error('екран: стан пише лише Екран.змінити'); },
    deleteProperty(){ throw new Error('екран: стан пише лише Екран.змінити'); }});

  /* Малювач бачить стан і попередні значення змінених ключів (`до`): перехід — це різниця, а не окрема змінна. */
  function малювач(назва, ключі, ф){ малювачі.push({назва, ключі, ф}); }
  /* Перемалювати названий малювач з поточного стану: розмітку під ним змінив не стан (вузол переїхав, список доріс). */
  function перемалювати(назва){
    for (const м of малювачі) if (м.назва === назва) м.ф(читач, Object.create(null));
  }

  function дія(назва, ф){
    if (дії[назва]) throw new Error('екран: дія «' + назва + '» уже є');
    дії[назва] = ф;
  }
  function виконати(назва, ...арг){
    if (!дії[назва]) throw new Error('екран: нема дії «' + назва + '»');
    return дії[назва](...арг);
  }
  /* Дія жінки: до першого входу в режим (профіль ще читається зі сховища) дотик нічого не робить. */
  function відЖінки(назва, ...арг){ return стан.вхід ? виконати(назва, ...арг) : undefined; }
  /* Прив'язка розмітки до дій: {ід: дія} на `click`, або {ід: [подія, дія]}. Обробник дістає подію й елемент. */
  function слухати(таблиця){
    for (const [ід, що] of Object.entries(таблиця)){
      const е = document.getElementById(ід); if (!е) continue;
      const [подія, назва] = Array.isArray(що) ? що : ['click', що];
      е.addEventListener(подія, п => відЖінки(назва, п, е));
    }
  }

  return {стан: читач, змінити, малювач, перемалювати, дія, виконати, відЖінки, слухати};
})();
