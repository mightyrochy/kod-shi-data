/* Прапорці екрана: `рукою` — вона попросила картку, поки в ній порожньо; `порожні` — рядок «Додати» відкрив порожні
   рядки; `зони` — плитка «Відвести погляд від…» відкрила чипи зон; `свій` — відкрито поле свого відтінку губ. */
function прапорСценарію(назва, так){
  const с = Екран.стан.сценарій || {};
  if (!!с[назва] !== !!так) Екран.змінити({сценарій: Object.assign({}, с, {[назва]: !!так})});
}
