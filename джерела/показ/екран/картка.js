function чипРяд(конт, поле, поз, варіанти, класи, класРяду){
  const ряд = ел('div', 'ряд' + (класРяду ? ' ' + класРяду : ''));
  /* РЯД ПІДПИСАНИЙ ПОЛЕМ І ПОЗИЦІЄЮ (КВ-2): так шукач ІНШОГО чипа (прилад,
     сторонній читач DOM) бере чип за КОДОМ осі, а не за написом на екрані —
     напис КВ-2 скоротив, код (`dataset.код`) лишився внутрішньою мовою (п.12). */
  ряд.dataset.поле = поле; ряд.dataset.поз = String(поз);
  /* ПЕРЕМАЛЬОВАНА КАРТКА ПОКАЗУЄ ОБРАНЕ (КВ-1): питання над полем іде за станом, і чип, що
     згас після перемальовування при живому стані, показав би питання не до того дотику */
  const вс = В[поз];
  варіанти.forEach((я,і)=>{
    const с = ел('span', 'чип'+(класи&&класи[і]?(' '+класи[і]):''));
    с.setAttribute('role', 'button'); с.tabIndex = 0;
    /* НАПИС НА ЕКРАНІ Й ЗАПИС — ДВА РІЗНІ РЯДКИ (КВ-2): `коротко` — те, що влазить
       у ряд на 390 px; `dataset.з` лишається ПОВНИМ ярликом, бо його читають
       калібрування (`вердикт_у_ребра`), плитка бібліотеки й колонка журналу. */
    текстЖінціП(с, (typeof я==='object') ? (я.коротко||я.тема||я.ярлик||'') : я, 'card_statement_failed', своїЕкрануП());
    с.dataset.з = (typeof я==='object') ? (я.тема||я.ярлик||'') : я;
    if (typeof я==='object' && я.код) с.dataset.код = я.код;
    if (typeof я==='object' && я.мінус) с.classList.add('лише-мінус');
    if (вс && (поле === 'аспекти' ? (вс.аспекти || []).includes(с.dataset.код)
                                   : (поле !== 'ок' && поле !== 'ні' && вс[поле] === с.dataset.з)))
      с.classList.add('вибр');
    станВиборуП(с);
    с.onclick = () => Екран.відЖінки('картка-чип', ряд, с, поз, поле);
    с.onkeydown = е => Екран.відЖінки('картка-чип-клавіша', е, с);
    ряд.appendChild(с);
  });
  конт.appendChild(ряд);
}

