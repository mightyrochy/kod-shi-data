/* ── ЕКРАН: ПЕРЕХІДНЕ ──────────────────────────────────────────────────────
   Екрани, яких ще не переписано на ядро, живуть у старих файлах `показ/*.js` і самі на стан не підписані: навігація
   наповнює їх цим викликом після входу в режим чи на крок. Кожен переписаний екран забирає звідси свій рядок і
   малює себе малювачем; порожня функція видаляється разом з останнім старим екраном. */
function наповнитиСтаріЕкрани(увійшла){
  const р = Екран.стан.режим;
  if (увійшла){
    /* «Усі образи» наповнює себе сам, якими б дверима не зайти */
    if (р === 'бібліотека' && window.оновитиБібліотеку) window.оновитиБібліотеку();
    /* Pyodide підіймається рівно тут і жодного разу раніше */
    if (р === 'палітра' && !ПАЛІТРА) оновитиПалітруП();
    /* екран оцінки малюється зі свого стану; Pyodide підіймається, поки вона обирає фото */
    if (р === 'оцінка') відкритиОцінкуП();
  }
  /* панель розмови й картка сценарію показують себе наново на кожен вхід у режим і на крок */
  показатиРозмову();
}
