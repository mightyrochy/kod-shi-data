/* ── ЕКРАН: ПЕРЕХІДНЕ ──────────────────────────────────────────────────────
   Екрани, яких ще не переписано на ядро, живуть у старих файлах `показ/*.js` і самі не підписуються на стан: тут —
   їхні виклики з нових файлів (`Старе`) і підписки, якими навігація їх наповнює. Кожен переписаний екран забирає
   звідси свої рядки; порожній файл видаляється разом з останнім старим екраном. */
const Старе = Екран.межа({
  /* профіль (`профілі.js`) */
  писатиАктивний: () => писатиАктивний,
  малюватиСмугу: () => малюватиСмугу,
  завершитиОнбординг: () => завершитиОнбординг,
  малюватиОгляд: () => малюватиОгляд,
  малюватиВирізку: () => малюватиВирізку,
  малюватиДрап: () => малюватиДрап,
  /* панель розмови й картка сценарію (`випадок.js`) */
  стерегтиПанель: () => стерегтиПанель,
  відступПідПанель: () => відступПідПанель,
  малюватиЧатП: () => малюватиЧатП,
  згорнутиРозмову: () => () => { ШІ_РОЗГОРНУТО = false; },
  /* збережені сценарії, усі образи, палітра, «Оціни мій образ» */
  оновитиСценарії: () => оновитиСценарії,
  оновитиБібліотеку: () => window.оновитиБібліотеку,
  оновитиПалітруП: () => оновитиПалітруП,
  єПалітраП: () => () => !!ПАЛІТРА,
  відкритиОцінкуП: () => відкритиОцінкуП,
}, 'старих екранів');

Екран.малювач('старі-екрани', ['режим', 'вхід', 'крок', 'вхід_кроку', 'широко', 'три'], (с, до) => {
  if (!с.вхід) return;
  const р = с.режим, увійшла = 'вхід' in до, наКрок = увійшла || 'вхід_кроку' in до;
  if (р === 'старт' && наКрок){
    if (КРОКИ_ЗНАЙОМСТВА[с.крок] === 'е-мірки') Старе.малюватиВирізку();
    if (КРОКИ_ЗНАЙОМСТВА[с.крок] === 'е-лице') Старе.малюватиДрап();
  }
  if (увійшла){
    if (р === 'профіль') Старе.малюватиОгляд();
    if (р === 'сценарії') Старе.оновитиСценарії();
    /* «Усі образи» наповнює себе сам, якими б дверима не зайти */
    if (р === 'бібліотека' && Старе.оновитиБібліотеку) Старе.оновитиБібліотеку();
    /* Pyodide підіймається рівно тут і жодного разу раніше */
    if (р === 'палітра' && !Старе.єПалітраП()) Старе.оновитиПалітруП();
    /* екран оцінки малюється зі свого стану; Pyodide підіймається, поки вона обирає фото */
    if (р === 'оцінка') Старе.відкритиОцінкуП();
    /* новий екран — панель розмови знову компактна */
    if (р !== 'сценарій') Старе.згорнутиРозмову();
  }
  Старе.малюватиЧатП();
});
