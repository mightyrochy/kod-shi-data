/* ── ЕКРАН: ФОТО ПРОФІЛЮ ───────────────────────────────────────────────────
   Два слоти — портрет і повний зріст. Що в слоті лежить, знає логіка (`показ/фото_профіль.js`: `оновитиФотоП`,
   `зберегтиФотоП`, `прибратиФотоП`); екран малює слот зі зрізу `фото` й сам читає знімок зі сховища лише для
   картинки. Шлях: вибір файла чи «Прибрати» → дія → логіка → `показатиПрофіль` → малювач. */
const СЛОТИ_ФОТО = {'ф-портрет': 'портрет', 'ф-зріст': 'зріст'};
Екран.дія('фото-обрати', (п, е, вид) => зберегтиФотоП(вид, е.files && е.files[0]));
Екран.дія('фото-прибрати', (п, е, вид) => { п.preventDefault(); п.stopPropagation(); return прибратиФотоП(вид); });

/* Адреса знімка для картинки (object URL) — слід малювача: звільняється з наступним малюванням. */
function адресиЗнімків(){
  let адреси = [];
  return {звільнити(){ адреси.forEach(u => { try{ URL.revokeObjectURL(u); }catch(_){} }); адреси = []; },
          нова(блоб){ const u = URL.createObjectURL(блоб); адреси.push(u); return u; }};
}
const адресиСлотів = адресиЗнімків();
Екран.малювач('слоти-фото', ['фото'], () => {
  const ф = зрізПрофіляП().фото;
  адресиСлотів.звільнити();
  for (const [конт, вид] of Object.entries(СЛОТИ_ФОТО)){
    const к = $(конт); if (!к) continue;
    к.innerHTML = '';
    const стан = ф.стан[вид], портрет = вид === 'портрет';
    if (стан === 'збій'){ const ст = ел('div', 'статус'); збійЖінціП(ст, 'photo_unreadable', причинаЗбоюФотоП(вид)); к.appendChild(ст); }
    const слот = ел('label', 'слот ' + (портрет ? 'арка' : 'полароїд'));
    if (стан === 'є'){
      const і = ел('img'); і.alt = ''; слот.appendChild(і);
      читатиКв(ключФото(вид)).then(б => { if (б && typeof б !== 'string' && і.isConnected) і.src = адресиСлотів.нова(б); })
        .catch(e => { збійЖінціП($('збій-стан'), 'photo_unreadable', e); });   /* знімок не прочитався — не порожня рамка мовчки */
    } else {
      const п = ел('span', 'порожньо');
      const б = ел('b'); б.appendChild(іконка('плюс')); п.appendChild(б);
      п.appendChild(ел('span', null, стан === 'збій' ? 'Обрати інше фото' : (портрет ? 'Додати портрет' : 'На повний зріст')));
      слот.appendChild(п);
    }
    const вх = ел('input'); вх.type = 'file'; вх.accept = 'image/*';
    вх.addEventListener('change', п => Екран.відЖінки('фото-обрати', п, вх, вид));
    слот.appendChild(вх);
    if (стан === 'є' || стан === 'старе'){
      const геть = ел('button', 'геть'); геть.type = 'button'; геть.title = 'Прибрати фото';
      геть.appendChild(іконка('хрестик'));
      геть.addEventListener('click', п => Екран.відЖінки('фото-прибрати', п, геть, вид));
      слот.appendChild(геть);
    }
    к.appendChild(слот);
  }
});
