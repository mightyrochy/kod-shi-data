/* ── ЕКРАН: ВЕРДИКТ І ПОЛЕ КОМЕНТАРЯ ───────────────────────────────────────
   Блок вердикту — один на картку образу й на «Оціни мій образ» (`поз` — номер картки або 'оц'): два ряди дотиків,
   питання над полем, поле з голосом, «або коротко» аспекти, рядок статусу під кнопкою й згорнутий «Твій коментар».
   Відповідь картки (`В[поз]`: дотики, її слова, що записано) — модель логіки (`картки.js`); тут — вузли й дії.
   СТАН ЕКРАНА (усе — об'єкти за позиціями, замінювані цілим: кілька карток за один прохід не губляться):
   · `вердикт` — лічильник «блок показати наново»: логіка кличе `показатиВердикт(поз)` після кожного запису у
     відповідь, від якого залежить питання, приклад у полі, порада, аспекти чи записаний коментар
     (`полеВердиктуЗміненоП`, `картки.js`). Малювач бере все зі свіжої `відповідь(поз)` її читачами (`ключПоляП`,
     `знакАспектівП`, `рядокПорадиП`); поле з її словами пише лише тоді, коли воно розійшлося з моделлю (відкрито з
     бібліотеки) — того, що вона саме набирає, не чіпає.
   · `статус_вердикту` — рядок під «Записати вердикт»: `{код, подій}`. Логіка каже, ЩО сталось, кодом
     (`показатиСтатусВердикту(поз, код)`), слова — таблиця й шаблони збою тут. Пишеться на подію: у той самий вузол
     пишуть і заміна речі, і запис оцінки.
   · `підказка_вердикту` — рядок під аспектами: коментар позначив річ на заміну або не прочитаний; так само на подію.
   · `фокус_вердикту` — рамка поля після дотику «Вдягнеш?» (`рамка`) і прокрутка до питання над ним (`подій`). */
Екран.змінити({вердикт: {}, статус_вердикту: {}, підказка_вердикту: {}, фокус_вердикту: {}});

/* ── імена, якими логіка каже про зміну своїх даних ── */
function показатиВердикт(поз){
  Екран.змінити({вердикт: {...Екран.стан.вердикт, [поз]: Number(Екран.стан.вердикт[поз] || 0) + 1}});
}
const подіяПозиції = (зріз, поз, поля) => ({...зріз, [поз]: {...поля, подій: Number((зріз[поз] || {}).подій || 0) + 1}});
function показатиСтатусВердикту(поз, код){
  Екран.змінити({статус_вердикту: подіяПозиції(Екран.стан.статус_вердикту, поз, {код})});
}
function показатиПідказкуВердикту(поз, код){
  Екран.змінити({підказка_вердикту: подіяПозиції(Екран.стан.підказка_вердикту, поз, {код})});
}
/* Поле — фокус: прокрутка так, щоб питання й поле лягли в екран, і рамка. `.focus()` НЕ кличемо навмисно: на телефоні
   це відкрило б клавіатуру й закрило пів екрана, а вона, можливо, лише хотіла поставити дотик. */
function показатиФокусВердикту(поз){
  Екран.змінити({фокус_вердикту: подіяПозиції(Екран.стан.фокус_вердикту, поз, {рамка: true})});
}
/* Ключ стану — рядок; номер картки логіка тримає числом (`typeof поз === 'number'` — картка образу, не оцінка). */
const позиціяВердикту = ключ => /^\d+$/.test(ключ) ? Number(ключ) : ключ;
/* Позиції, чия подія виросла проти `до`; `Екран.перемалювати` (без `до`) разового не повторює. */
function зПодією(зріз, до){
  return до ? Object.keys(зріз).filter(поз => (до[поз] || {}).подій !== зріз[поз].подій) : [];
}

/* поле росте з текстом: довгий коментар видно цілим, без внутрішньої прокрутки на телефоні */
function ростиПолеП(та){
  та.style.height = 'auto';
  та.style.height = Math.min(Math.max(та.scrollHeight + 2, 0), 480) + 'px';
}

/* ── блок: питання, приклад, порада, аспекти, її слова ──
   `корінь` — блок, ще не вставлений у сторінку (картку будують цілою й лише тоді вставляють): `$` шукає в документі
   й там його ще нема — без кореня питання над полем лишалось порожнім до першого дотику. */
function малюватиПолеВердикту(поз, корінь){
  const знайти = ід => корінь ? корінь.querySelector('[id="' + ід + '"]') : $(ід);
  const в = відповідь(поз), к = ключПоляП(в), знак = знакАспектівП(в);
  const п = знайти('пит-поля-' + поз); if (п) текстЖінціП(п, ПИТАННЯ_ПОЛЯ_П[к]);
  const та = знайти('ком-' + поз);
  if (та){
    текстЖінціП(та, ПРИКЛАД_ПОЛЯ_П[к] || ПРИКЛАД_ПОЛЯ_П[в.верд_код] || ПРИКЛАД_ПОЛЯ_П.start, undefined, undefined, 'placeholder');
    if (та.value !== (в.коментар || '')){ їїСловаП(та, в.коментар, 'value'); if (!корінь) ростиПолеП(та); }
  }
  const пр = знайти('порада-поля-' + поз);
  if (пр) текстЖінціП(пр, рядокПорадиП(поз, в, !!(пр.dataset.неЦя && (в.верд_код === 'one_change' || в.верд_код === 'no')), знак), 'card_verdict_hint_failed');
  if (!корінь) малюватиЗаписанийКоментар(поз);
  const б = знайти('аспекти-' + поз); if (!б) return;
  б.style.display = знак ? '' : 'none';
  const м = знайти('аспекти-мітка-' + поз); if (м && знак) текстЖінціП(м, АСПЕКТИ_МІТКА_П[знак]);
  б.querySelectorAll('.чип.лише-мінус').forEach(ч => { ч.style.display = знак === 'minus' ? '' : 'none'; });
  /* знак змінився — логіка зняла обрані аспекти (`узгодитиЗнакАспектівП`), і це видно: чипи гаснуть під новою міткою */
  б.querySelectorAll('.ряд[data-поле="аспекти"] .чип').forEach(ч => {
    ч.classList.toggle('вибр', (в.аспекти || []).includes(ч.dataset.код)); станВиборуП(ч); });
}
/* ЇЇ СЛОВА ПІСЛЯ ЗАПИСУ. Після «Записати вердикт» під кнопкою стояло лише «Записано.», а що саме
   записано — вона не бачила (коментар записувався правильно, `good=colour`, але речення зникало з очей). Тепер
   під статусом — згорнутий рядок «Твій коментар»: торкнулась — читає свої слова ЦІЛИМИ, без обрізання (п.9).
   Текст — її власний (`коментар_записаний` відповіді — те, що лягло в запис), код його не пише й не читає; без
   коментаря рядка нема. */
function малюватиЗаписанийКоментар(поз){
  const ст = $('вст-' + поз); if (!ст) return;
  let бл = $('ком-запис-' + поз);
  if (!String(відповідь(поз).коментар_записаний || '').trim()){ if (бл) бл.remove(); return; }
  if (!бл){
    бл = ел('details', 'ком-запис'); бл.id = 'ком-запис-' + поз;
    бл.appendChild(ел('summary', null, 'Твій коментар'));
    бл.appendChild(ел('p', 'ком-запис-текст'));
    ст.insertAdjacentElement('afterend', бл);
  }
  їїСловаП(бл.querySelector('p'), відповідь(поз).коментар_записаний.trim());
}
Екран.малювач('поле-вердикту', ['вердикт'], (с, до) => {
  for (const поз of Object.keys(с.вердикт)){
    if ((до.вердикт || {})[поз] !== с.вердикт[поз]) малюватиПолеВердикту(позиціяВердикту(поз));
  }
});

/* ── рядок статусу під кнопкою ── */
const НАПИС_СТАТУСУ_ВЕРДИКТУ = {нема_що: НЕМА_ЩО_ЗАПИСАТИ_П, читає: 'Стилістка читає твій коментар…', записано: 'Записано.'};
Екран.малювач('статус-вердикту', ['статус_вердикту'], (с, до) => {
  for (const поз of зПодією(с.статус_вердикту, до.статус_вердикту)){
    const вузол = $('вст-' + поз), код = с.статус_вердикту[поз].код; if (!вузол) continue;
    /* збій: слід лишила логіка (`збійЖінціП(null, …)`), тут — шаблон заяви коду */
    if (код === 'не_записався') текстЖінціП(вузол, ШАБЛОНИ_ЗБОЮ_П.verdict_not_saved);
    else if (код === 'не_записалось') текстЖінціП(вузол, ШАБЛОНИ_ЗБОЮ_П.not_written);
    else текстЖінціП(вузол, НАПИС_СТАТУСУ_ВЕРДИКТУ[код] || '');
  }
});
/* ── рядок під аспектами: що коментар зробив ── */
Екран.малювач('підказка-вердикту', ['підказка_вердикту'], (с, до) => {
  for (const поз of зПодією(с.підказка_вердикту, до.підказка_вердикту)){
    const вузол = $('верд-підказка-' + поз), код = с.підказка_вердикту[поз].код; if (!вузол) continue;
    if (код === 'не_ця') текстЖінціП(вузол, рядокНеЦяП(рукаПозП(поз)));
    else if (код === 'коментар_не_прочитано') текстЖінціП(вузол, ШАБЛОНИ_ЗБОЮ_П.comment_not_read);
    else текстЖінціП(вузол, '');
  }
});
/* ── рамка й прокрутка до поля ── */
Екран.малювач('фокус-вердикту', ['фокус_вердикту'], (с, до) => {
  for (const поз of зПодією(с.фокус_вердикту, до.фокус_вердикту)){
    const та = $('ком-' + поз), п = $('пит-поля-' + поз); if (!та || !п) continue;
    та.classList.toggle('в-фокус', !!с.фокус_вердикту[поз].рамка);
    if (!с.фокус_вердикту[поз].рамка || typeof п.scrollIntoView !== 'function') continue;
    const тихо = !!(window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches);
    п.scrollIntoView({block: 'start', behavior: тихо ? 'auto' : 'smooth'});
  }
});

/* ── дії поля ──
   ОЦІН-1: рамка-фокус гасне, щойно вона торкнулась поля; на виході з поля текст дописується в той самий запис (щоб
   слова не пропали, коли вона просто погортала далі); пауза в друку — одне м'яке «що саме?», якщо коротко. Що з цього
   випливає для запису, знає логіка (`коментарНабраноП`, `коментарЗалишеноП`, `коментарНадиктованоП`). */
const позиціяПоляВердикту = вузол => позиціяВердикту(вузол.id.slice('ком-'.length));
Екран.дія('вердикт-поле-фокус', (_, вузол) => {
  const поз = позиціяПоляВердикту(вузол);
  if ((Екран.стан.фокус_вердикту[поз] || {}).рамка)
    Екран.змінити({фокус_вердикту: подіяПозиції(Екран.стан.фокус_вердикту, поз, {рамка: false})});
});
Екран.дія('вердикт-поле-вихід', (_, вузол) => коментарЗалишеноП(позиціяПоляВердикту(вузол)));
Екран.дія('вердикт-поле-ввід', (_, вузол) => {
  const поз = позиціяПоляВердикту(вузол);
  записатиКоментарВердиктуП(поз, $('ком-' + поз).value);
  коментарНабраноП(поз);
  ростиПолеП($('ком-' + поз));
});
/* Прив'язує поле до таблиці дій, щойно блок стоїть у сторінці (картка — з `підвʼязатиКартку`, оцінка — після вставки
   свого блока); повторна прив'язка того самого вузла нічого не додає. */
const ПРИВʼЯЗАНІ_ПОЛЯ_ВЕРДИКТУ = new WeakSet();
function підвʼязатиВердикт(поз){
  const ід = 'ком-' + поз, вузол = $(ід);
  if (!вузол || ПРИВʼЯЗАНІ_ПОЛЯ_ВЕРДИКТУ.has(вузол)) return;
  Екран.слухати({[ід]: ['focus', 'вердикт-поле-фокус']});
  Екран.слухати({[ід]: ['blur', 'вердикт-поле-вихід']});
  Екран.слухати({[ід]: ['input', 'вердикт-поле-ввід']});
  ПРИВʼЯЗАНІ_ПОЛЯ_ВЕРДИКТУ.add(вузол);
}

/* ДВІ КАРТКИ, ОДИН БЛОК: картка образу й «Оціни мій образ» будують вердикт тут (доти — двома
   копіями, що вже розходились підказкою). `неЦя` — на картці є позначка «не ця» на речі. */
function вердиктДотикиЙПолеП(в, поз, неЦя){
  в.appendChild(ел('div', 'мітка мітка-дотику', 'Вдягнеш?'));
  чипРяд(в, 'верд', поз, ВЕРДИКТ_П, ['ок вісь', 'вісь', 'ні вісь'], 'ряд-осі');
  /* РОЗРІЗНЯЛЬНЕ ПИТАННЯ: продукт обіцяє «те, що пасує ТОБІ», а не «гарний
     образ узагалі» — і лише це питання відрізняє одне від іншого у вердикті. */
  в.appendChild(ел('div', 'мітка мітка-дотику', 'Це саме твоє — чи просто гарний образ?'));
  чипРяд(в, 'для_мене', поз, МОЄ_П, МОЄ_П.map(() => 'вісь'), 'ряд-осі');
  const пит = ел('label', 'мітка питання-поля'); пит.id = 'пит-поля-' + поз; пит.htmlFor = 'ком-' + поз;
  в.appendChild(пит);
  const пр = ел('p', 'підказка порада-поля'); пр.id = 'порада-поля-' + поз;
  if (неЦя) пр.dataset.неЦя = '1';
  в.appendChild(пр);
  const та = ел('textarea', 'коробка поле-вердикту'); та.id = 'ком-' + поз; та.rows = 5;
  в.appendChild(та);
  /* ГОЛОС НА ВЕРДИКТІ (слово власника 24.09: «поле, де тестувальники записують вердикт»).
     Текст лягає в те саме `відповідь(поз).коментар`, що й з клавіатури. */
  { const гр = ел('div', 'голос-ряд');
    const мк = ел('button', 'мікрофон'); мк.type = 'button'; мк.id = 'мік-ком-' + поз;
    мк.setAttribute('aria-pressed', 'false'); мк.setAttribute('aria-label', 'Сказати голосом');
    мк.innerHTML = '<svg class="і"><use href="#і-мікрофон"/></svg>';
    гр.appendChild(мк);
    гр.appendChild(ел('span', 'підпис-голосу', 'або скажи голосом — це швидше'));
    в.appendChild(гр);
    const гн = ел('div', 'статус'); гн.id = 'голос-ком-' + поз; в.appendChild(гн);
    привʼязатиГолос({кнопка: мк, поле: та, нота: гн,
                     після: () => { записатиКоментарВердиктуП(поз, та.value); коментарНадиктованоП(поз); ростиПолеП(та); }});
  }
  /* аспекти — під полем і тихіше за нього: це «або коротко», а не третє питання */
  const б = ел('div', 'аспекти-вердикту'); б.id = 'аспекти-' + поз; б.style.display = 'none';
  const м = ел('div', 'мітка-тиха'); м.id = 'аспекти-мітка-' + поз; б.appendChild(м);
  чипРяд(б, 'аспекти', поз, АСПЕКТИ_ВЕРДИКТУ_П, АСПЕКТИ_ВЕРДИКТУ_П.map(() => 'дрібний'));
  const пд = ел('div', 'статус'); пд.id = 'верд-підказка-' + поз; б.appendChild(пд);
  в.appendChild(б);
  малюватиПолеВердикту(поз, в);
}
