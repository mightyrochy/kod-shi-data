/* ── ЕКРАН: СПОВІЩЕННЯ ЗБОЮ (перепис екрана, зріз 10) ──────────────────────
   Збій, що не має свого місця на екрані (запис профілю, фото, чернетки, образу; читання сховища; позначка
   диктування; скасування дії), жінка бачить в одній панелі `збій-панель` над усім. Логіка й решта екрана кличуть
   ім'я `показатиЗбійЗапису(вид, причина)` і вузла не знають: слід збою й шаблон за видом — точка виходу
   (`збійЖінціП`), місце панелі — тут. Доти логіка сама брала вузол `збій-стан`, а панель переносила точка
   виходу в `мовний_шар.js`. */
/* Сповіщення лишається видимим і доступним усередині відкритого редактора: аркуш робить решту сторінки
   неактивною, тож панель переїжджає в нього (назад її повертає `знятиАркуш`, `екран/навігація.js`). */
function виставитиПанельЗбою(){
  const панель = $('збій-панель'), аркуш = $('аркуш');
  if (!панель) return;
  (аркуш && !аркуш.hidden ? аркуш : document.body).appendChild(панель);
  панель.removeAttribute('inert');
}
function показатиЗбійЗапису(вид, причина){
  виставитиПанельЗбою();
  return збійЖінціП($('збій-стан'), вид, причина);
}
