/* ── ЕКРАН: ТЕМА ───────────────────────────────────────────────────────────
   Удень «полотно й нитка», уночі «музейне золото». Системну бере сама; кнопка в шапці (на ноутбуці — ще внизу бічної
   панелі) перемикає й запам'ятовує вибір на цьому телефоні (`localStorage`, ключ `люстерко-тема`; до першого малювання
   його читає рядок у `<head>` — щоб не блимало). До збирання образів тема стосунку не має: логіки під нею нема, стан —
   ключ `тема` ('темна' | 'світла'), і все, що малюється з кольорів теми (огляд профілю), стоїть на цьому ключі. */
const КЛЮЧ_ТЕМИ = 'люстерко-тема';
const системнаТема = () => typeof window.matchMedia === 'function'
  && window.matchMedia('(prefers-color-scheme: dark)').matches ? 'темна' : 'світла';
const поточнаТема = () => document.documentElement.dataset.тема || системнаТема();

Екран.дія('тема-перемкнути', () => {
  const нова = поточнаТема() === 'темна' ? 'світла' : 'темна';
  document.documentElement.dataset.тема = нова;
  try { localStorage.setItem(КЛЮЧ_ТЕМИ, нова); } catch(e){}
  Екран.змінити({тема: нова});
});
Екран.слухати({'тема-кнопка': 'тема-перемкнути', 'бік-тема': 'тема-перемкнути'});

const НАПИСИ_ТЕМИ = {темна: {кнопка: 'День', підпис: 'Світла тема', смуга: '#141517'},
                     світла: {кнопка: 'Ніч', підпис: 'Темна тема', смуга: '#F4F0E8'}};
Екран.малювач('тема', ['тема'], с => {
  const н = НАПИСИ_ТЕМИ[с.тема === 'темна' ? 'темна' : 'світла'];
  $('тема-кнопка').setAttribute('aria-label', н.підпис);
  $('тема-текст').textContent = н.кнопка; $('бік-тема-текст').textContent = н.кнопка;
  const мета = document.querySelector('meta[name="theme-color"]'); if (мета) мета.setAttribute('content', н.смуга);
});
Екран.змінити({тема: поточнаТема()});
