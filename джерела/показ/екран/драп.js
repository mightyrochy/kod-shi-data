/* ── ЕКРАН: «ЩО ТОБІ ДО ЛИЦЯ» ──────────────────────────────────────────────
   Стимульна елісітація, не опитування пам'яті: людина має бачити своє обличчя між двома полями. Питання й варіанти —
   `ДРАП_ПОЛЯ`, відповіді — `ДРАП`, кадр обличчя у вікні — `КАДР` (усе — логіка, `показ/фото_профіль.js`); екран
   малює крок зі зрізів `драп`, `колір`, `фото` і кадр — зі зрізу `кадр`. Шлях: дотик до варіанта → дія →
   `відповістиДрапП` → `показатиПрофіль` → малювач; повзунок кадру → `записатиКадрП`, відпущено — `писатиКадр`. */
const ПОВЗУНКИ_КАДРУ = {'кд-м': 'масштаб', 'кд-x': 'x', 'кд-y': 'y'};
Екран.дія('драп-відповісти', (п, е, поле, ключ) => відповістиДрапП(поле, ключ));
Екран.дія('драп-скинути', () => скинутиДрапП());
Екран.дія('кадр-зсунути', (п, е) => записатиКадрП(ПОВЗУНКИ_КАДРУ[е.id], е.value));
Екран.дія('кадр-відпущено', () => писатиКадр());

/* Обличчя у вікні: без масштабу й зсуву кружок показував би вухо. */
function стильКадру(і, к){
  const м = Number(к.масштаб) / 100;
  і.style.width = '100%'; і.style.height = '100%';
  і.style.transformOrigin = 'center';
  і.style.transform = 'scale(' + м + ') translate('
    + ((50 - Number(к.x)) / м).toFixed(2) + '%,' + ((50 - Number(к.y)) / м).toFixed(2) + '%)';
}
const адресиДрапу = адресиЗнімків();
/* Варіант відповіді: вузол, який і дотиком, і клавішею кладе ту саму відповідь. */
function варіантДрапу(вузол, поле, ключ){
  вузол.addEventListener('click', п => Екран.відЖінки('драп-відповісти', п, вузол, поле, ключ));
  return вузол;
}
function чипДрапу(чип, поле, ключ){
  чип.setAttribute('role', 'button'); чип.tabIndex = 0; станВиборуП(чип);
  чип.addEventListener('keydown', e => { if (e.key === 'Enter' || e.key === ' '){ e.preventDefault(); чип.click(); } });
  return варіантДрапу(чип, поле, ключ);
}
Екран.малювач('драп', ['драп', 'колір', 'фото'], () => {
  const с = зрізПрофіляП(), драп = с.драп, портрет = с.фото.портрет;
  if (!$('др-тіло')) return;
  /* ── БЕЗ ПОРТРЕТА ПИТАННЯ ЛИШАЮТЬСЯ, ЛИШЕ МІНЯЮТЬ ФОРМУ ──
     Самі три питання — САМОЗВІТ (K-IO-02): який метал біля обличчя кращий, який білий, теплі чи холодні нейтралі.
     Портрет робить їх ТОЧНІШИМИ (вона бачить своє обличчя між двома кольорами й відповідає оком, а не пам'яттю),
     але не потрібен, щоб відповісти: код приймає ці відповіді полем `драп` і без фото (рекомендованих основ 20 → 17).
     ЗАМКА НЕМА (п.9): без знімка ті самі питання стоять чипами зі зразком кольору, а рядок над ними каже, що з
     портретом вони точніші, — причина, а не заборона. З портретом — диптих із обличчям у вікні, повзунки кадру,
     «не бачу різниці» окремим рядком. */
  /* «кольори є» має два шляхи — портрет і відповідь чат-помічника (`КОЛІР.джерело`); без портрета, але з
     кольорами, екран каже, що кольори є і звідки, а не «Портрета ще нема» (живий прогін 13.11, вада 7) */
  const кольориЄ = !!(с.колір.шкіра && с.колір.волосся && с.колір.очі);
  const звідки = {чат: ' — з відповіді чат-помічника', портрет: ' — з портрета'}[с.колір.джерело] || '';
  $('др-нема').textContent = портрет ? ''
    : кольориЄ
    ? 'Кольори вже є' + звідки + '. На ці питання відповідай словами — стилістка їх приймає. '
      + 'Якщо додаси портрет, побачиш своє обличчя між двома кольорами й відповіси оком, а не пам\'яттю.'
    : 'Портрета ще нема — на ці питання можна відповісти словами, і стилістка їх приймає. '
      + 'З портретом вони стають точнішими: ти бачиш своє обличчя між двома кольорами '
      + 'й відповідаєш оком, а не пам\'яттю.';
  $('др-нема').style.display = портрет ? 'none' : 'block';
  if (с.фото.стан.портрет === 'збій') збійЖінціП($('др-нема'), 'photo_unreadable', причинаЗбоюФотоП('портрет'));
  $('др-тіло').style.display = 'block';
  const тіло = $('др-тіло'); тіло.innerHTML = '';
  адресиДрапу.звільнити();

  if (портрет){
    const пк = ел('div');
    розміткаЖінціП(пк, '<div class="фото-назва" style="margin-top:14px">Підведи обличчя в кружок</div>'
      + '<div class="кадр"><span id="кд-м-підпис">Масштаб</span><input type="range" id="кд-м" aria-labelledby="кд-м-підпис" min="100" max="320" value="' + Number(с.кадр.масштаб) + '"></div>'
      + '<div class="кадр"><span id="кд-x-підпис">Ліво-право</span><input type="range" id="кд-x" aria-labelledby="кд-x-підпис" min="0" max="100" value="' + Number(с.кадр.x) + '"></div>'
      + '<div class="кадр"><span id="кд-y-підпис">Вгору-вниз</span><input type="range" id="кд-y" aria-labelledby="кд-y-підпис" min="0" max="100" value="' + Number(с.кадр.y) + '"></div>');
    тіло.appendChild(пк);
    for (const ід of Object.keys(ПОВЗУНКИ_КАДРУ)){ const е = $(ід);
      е.addEventListener('input', п => Екран.відЖінки('кадр-зсунути', п, е));
      е.addEventListener('change', п => Екран.відЖінки('кадр-відпущено', п, е)); }
  }
  const вікна = [];
  for (const поле of ДОВІДНИК.показ.групи_драпу){
    const оп = ДРАП_ПОЛЯ[поле];
    const н = елЖінціП('div', 'мітка', оп.питання); н.style.margin = '24px 0 8px';
    тіло.appendChild(н);
    const проби = оп.в.filter(в => в.hex || !оп.стимул);
    const нуль = оп.в.find(в => !в.hex && оп.стимул);
    if (оп.стимул && !портрет){
      /* САМОЗВІТ: ті самі значення, той самий запис, лише без вікна з обличчям. Зразок кольору в чипі лишається
         стимулом — жінка бачить, про яке саме золото й який саме білий її питають, а не згадує слово. */
      const р = ел('div', 'ряд');
      оп.в.forEach(в => {
        const ч = ел('span', 'чип' + (драп[поле] === в.ключ ? ' вибр' : ''));
        if (в.hex){ const з = ел('span', 'зразки'); const i_ = ел('i'); i_.style.background = в.hex; з.appendChild(i_); ч.appendChild(з); }
        { const тв = document.createTextNode(''); текстЖінціП(тв, в.підпис, undefined, undefined, 'data'); ч.appendChild(тв); }
        р.appendChild(чипДрапу(ч, поле, в.ключ));
      });
      тіло.appendChild(р);
    } else if (оп.стимул){
      const д = ел('div', 'диптих');
      проби.forEach(в => {
        const б = ел('button', 'стулка'); б.type = 'button';
        б.setAttribute('aria-pressed', драп[поле] === в.ключ ? 'true' : 'false');
        const п = ел('span', 'поле-тло'); п.style.background = в.hex;
        const вк = ел('span', 'вікно');
        const і = ел('img'); і.alt = ''; стильКадру(і, с.кадр); вікна.push(і);
        вк.appendChild(і); п.appendChild(вк);
        б.appendChild(п); б.appendChild(елЖінціП('span', 'назва', в.підпис));
        д.appendChild(варіантДрапу(б, поле, в.ключ));
      });
      тіло.appendChild(д);
      if (нуль){
        const т = елЖінціП('button', 'текст однаково', (драп[поле] === нуль.ключ ? '✓ ' : '') + нуль.підпис); т.type = 'button';
        т.setAttribute('aria-pressed', драп[поле] === нуль.ключ ? 'true' : 'false');
        тіло.appendChild(варіантДрапу(т, поле, нуль.ключ));
      }
    } else {
      /* барви — не про колір біля обличчя, а про саму людину: чипи, не проби */
      const р = ел('div', 'ряд');
      оп.в.forEach(в => р.appendChild(чипДрапу(ел('span', 'чип' + (драп[поле] === в.ключ ? ' вибр' : ''), в.підпис), поле, в.ключ)));
      тіло.appendChild(р);
    }
  }
  if (вікна.length) читатиКв(ключФото('портрет')).then(б => {
    if (!б || typeof б === 'string' || !вікна[0].isConnected) return;
    const u = адресиДрапу.нова(б); вікна.forEach(і => { і.src = u; }); })
    .catch(e => { показатиЗбійЗапису('photo_unreadable', e); });   /* портрет не прочитався — не порожні вікна мовчки */
  const ст = ел('div', 'статус'); ст.id = 'др-стан'; ст.style.marginTop = '20px';
  const г = ДОВІДНИК.показ.групи_драпу.filter(к => драп[к]).length;
  текстЖінціП(ст, 'Відповіла на ' + г + ' з 4.');
  тіло.appendChild(ст);
  const скид = ел('button', 'текст', 'Скинути відповіді'); скид.type = 'button';
  скид.addEventListener('click', п => Екран.відЖінки('драп-скинути', п, скид));
  тіло.appendChild(скид);
});
/* КАДР: повзунок рухає обличчя в усіх вікнах одразу; сам повзунок малювач не чіпає, поки число те саме. */
Екран.малювач('кадр-драпу', ['кадр'], () => {
  const к = зрізПрофіляП().кадр;
  document.querySelectorAll('#др-тіло .вікно img').forEach(і => стильКадру(і, к));
  for (const [ід, що] of Object.entries(ПОВЗУНКИ_КАДРУ)){ const е = $(ід); if (е && parseInt(е.value) !== к[що]) е.value = Number(к[що]); }
});
