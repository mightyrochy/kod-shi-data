  /* ЗВЕДЕННЯ ДОТИКІВ І СЛІВ (КВ-1) — одне місце для читачів вердикту; без слів — самі дотики */
  if (!авто) запис.зведено = зведенийВердиктП(в, запис.коментар_внутрішня);
