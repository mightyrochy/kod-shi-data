/* ── ІНСТРУМЕНТИ РОЗМОВИ: ВИКОНАННЯ ВИКЛИКУ Й КАРТКА РЕЗУЛЬТАТУ (корінь Е2-усе-з-розмови) ──
   Перелік інструментів і договір виклику — одне джерело в Python (`conversation_tools.ІНСТРУМЕНТИ`): мовна модель
   кладе в хід `tool: {name, args}`, міст мови перевіряє його схемою звідти й віддає сюди лише прийнятий виклик
   (`хід.частини.tool`). Тут — лише відповідність імені функції продукту: та сама функція, яку кличе кнопка вікна, без
   другої копії логіки; картку під реплікою малює малювач `стрічка` (`екран/розмова.js`). */
/* Виконати прийнятий виклик → результат для картки (поля `вихід` запису переліку). Кожен інструмент — прямий виклик
   функції продукту, яку кличе й кнопка вікна: кнопка «Зберегти» форми сценарію (`фото_профіль.js`, `_зб`) кличе ту саму
   `зберегтиСценарій`; назва — її ввід: оновлення лишає назву відкритого сценарію (поле форми нею заповнене), новий —
   без назви, доки вона не дасть її у формі. Збій функції розмови не зупиняє: картка каже «не вдалося», а причина — у
   записі ходу (`запис.інструмент_збій`) для звіту власника. */
async function інструментомП(виклик, запис){
  const ім = виклик && виклик.name, а = (виклик && виклик.args) || {};
  try{
    if (ім === 'save_scenario'){
      const якНовий = а.as_new === true;
      const з = await зберегтиСценарій(якНовий ? '' : (СЦ.назва || ''), якНовий);
      return {tool: ім, done: true, as_new: якНовий, name: з.назва, час: з.час};
    }
    /* Збережені сценарії — ті самі функції, що й «Збережені» (`бібліотека.js`): перелік (`оновитиСценарії`, рядки —
       `кнопкаСценаріюП`, `екран/збережені.js`), відкрити (дотик рядка — `відкритиСценарій`), видалити (другий дотик «видалити» —
       `видалитиСценарій`), новий (кнопка «Новий» — `новийСценарій`). Ід — з переліку ходу (`saved_cases`), договір
       Python уже звірив його з цим переліком; запису за ним нема (видалено між ходом і викликом) — «не знайшла». */
    if (ім === 'list_scenarios'){
      const іди = await оновитиСценарії();
      if (!іди) throw new Error('scenarios_unreadable');
      /* у картці — рядки збережених за ід (ті самі записи й кнопки, що в «Збережених»), і скільки їх */
      return {tool: ім, done: true, scenarios: іди, кількість: іди.length};
    }
    if (ім === 'open_scenario' || ім === 'delete_scenario'){
      const с = (await усіСценарії()).find(з => з.ід === а.id);
      if (!с) return {tool: ім, done: false, знайдено: false};
      const ок = ім === 'open_scenario' ? await відкритиСценарій(а.id) : await видалитиСценарій(а.id);
      return Object.assign({tool: ім, done: ок === true, name: с.назва || '', час: с.час || null},
                           ім === 'open_scenario' && ок === true ? {заміна: true} : {});
    }
    if (ім === 'new_scenario'){
      const ок = новийСценарій();
      return {tool: ім, done: ок === true, заміна: ок === true};
    }
    if (ім === 'switch_profile'){
      const п = ПРОФІЛІ.find(п => п.ід === а.id);
      if (!п) return {tool: ім, done: false, збій: 'profile_not_found'};
      const ок = await перемкнути(а.id, виклик);
      return {tool: ім, done: ок === true, name: п.назва || '', номер: ПРОФІЛІ.indexOf(п),
              заміна: ок === true, збій: ок === true ? null : 'profile_switch_blocked'};
    }
    /* Паспорт нагоди й погода — ті самі функції, що кнопка «так» під «Усе правильно?» (`випадок.js`) і плитка відчуття
       «Коли й погода»; плитка за дотиком перемикає, тож обране вже відчуття лишається (дотик не знімає його). */
    if (ім === 'confirm_case'){
      const ок = підтвердитиРозумінняП();
      return {tool: ім, done: ок === true};
    }
    if (ім === 'set_weather_feel'){
      const обрано = ключВідчуттяП() === а.feel ? а.feel : обратиВідчуттяП(а.feel);
      return {tool: ім, done: обрано === а.feel, feel: обрано};
    }
    /* «ЗНАЙДИ МЕНІ ТАКУ» (наряд Функція-купити-річ): той самий каталог, що й «Оціни мій образ» (`вхідМостаП`), і той
       самий суд речі, що й її річ з фото (`пошук_речі` моста). Опис — коди, які договір мосту вже звірив зі схемою
       інструмента; слів її код не читає. Картка — рядки знайдених речей; що з них їй і котру першою — пише
       перекладач репліки з вердиктів речей (`item_verdicts`, заяви коду, п.12). */
    if (ім === 'find_item'){
      const р = await знайтиРічП(а);
      const варіанти = р.варіанти || [];
      if (запис) Object.assign(запис, {пошук_мс: р.мс, пошук_знайдено: варіанти.length, пошук_без_коду: р.без_коду || {}});
      return {tool: ім, done: true,
              варіанти: варіанти.map(в => ({id: в.ід, назва: в.назва || '', урл: в.url || '', ціна: в.ціна,
                                             фото: (в.фото || [])[0] || ''})),
              catalogue_search: Object.assign({result: р.повідомлення},
                варіанти.length ? {variants: варіанти.map(в => Object.assign(
                  {verdict: (в.вердикт || {}).повідомлення, slot: в.slot, item_type: в.item_type},
                  в.назва ? {item: {free_text: в.назва, lang: 'uk'}} : {}))} : {})};
    }
    if (запис) запис.інструмент_збій = 'unknown_tool: ' + ім;
  }catch(e){
    if (запис) запис.інструмент_збій = ім + ': ' + текстВинятку(e);
  }
  return {tool: ім, done: false};
}
/* Пошук речі в каталозі за кодами опису (`пошук_речі` моста): каталог сторінки, тіло й намір — той самий вхід моста,
   що в «Оціни мій образ»; каталогу на сторінці нема — збій, а не «нема». */
async function знайтиРічП(опис){
  if (!ЄДИНА_СТОРІНКА) throw new Error('no_catalog');
  return містП('пошук_речі', Object.assign(вхідМостаП(), {опис}));
}
/* Інструмент, що замінив сценарій або профіль (`заміна`), робить хід старого сценарію
   нечинним (`застосуватиСценарій` — нове покоління, хід розмови скасовано), а результат — відповідь на її ж прохання:
   репліка з карткою лягає в розмову сценарію, який тепер відкрито (кладе її хід), тут — решта кінця ходу: чернетка її
   зберігає, а кінець ходу «чат» — подія ядра, як у ходу, що дійшов до кінця (скасований хід її не дає). */
async function кінецьХодуЗаміниП(){
  написРозмовиП('');
  показатиРозмову(); await зберегтиЧернетку();
  завершитиДіюЯдра('чат', null);
}
/* Збій інструмента — сталим написом свого виду; «не знайшла» — ід, якого вже нема серед збережених. */
const ЗБІЙ_ІНСТРУМЕНТА_П = {save_scenario: 'not_saved', list_scenarios: 'scenarios_unreadable',
                            open_scenario: 'library_unreadable', delete_scenario: 'not_deleted', new_scenario: 'not_written',
                            switch_profile: 'profile_unreadable', confirm_case: 'not_written',
                            set_weather_feel: 'not_written', find_item: 'catalogue_search_failed'};
/* Картка результату під реплікою: підпис — той самий, що показує кнопка вікна; назва — її ввід (`назва`), без
   назви — підпис без назви з датою (`підписБезНазвиП`), як у «Збережених». */
function карткаІнструментаП(р){
  const к = ел('div', 'картка-інструмента');
  const назва = {назва: р.name || підписБезНазвиП(р.час)};
  if (р.tool === 'save_scenario' && р.done)
    текстЖінціП(к, підписЗНазвоюП(['Сценарій збережено як «', назва, '».']), 'tool_scenario_saved_failed');
  else if (р.tool === 'list_scenarios' && р.done){
    /* рядки — записи «Збережених» (`усіСценарії`) за ід результату, тими самими кнопками; видалений відтоді рядка не
       має, а збій читання — рядок збою під заголовком */
    const іди = р.scenarios || [];
    текстЖінціП(к.appendChild(ел('div')), р.кількість ? 'Збережені сценарії — ' + р.кількість + ':' : 'Збережених сценаріїв ще нема.', 'tool_scenarios_failed');
    if (іди.length) (async () => {
      try{
        const список = await усіСценарії();
        список.forEach(с => {
          if (!іди.includes(с.ід)) return;
          const н = ел('b'); назваСценаріюП(н, с.назва, с.час);
          к.appendChild(кнопкаСценаріюП(с, н));
        });
      }catch(e){ збійЖінціП(к.appendChild(ел('div')), 'scenarios_unreadable', e); }
    })();
  }
  else if (р.tool === 'open_scenario' && р.done)
    текстЖінціП(к, підписЗНазвоюП(['Відкрито сценарій «', назва, '».']), 'tool_scenario_opened_failed');
  else if (р.tool === 'delete_scenario' && р.done)
    текстЖінціП(к, підписЗНазвоюП(['Сценарій «', назва, '» видалено.']), 'tool_scenario_deleted_failed');
  else if (р.tool === 'new_scenario' && р.done)
    текстЖінціП(к, 'Почато новий сценарій.');
  else if (р.tool === 'switch_profile' && р.done)
    текстЖінціП(к, підписЗНазвоюП(['Відкрито профіль «', {назва: р.name || підписПрофілюП(р.номер)}, '».']), 'profile_unreadable');
  else if (р.tool === 'confirm_case' && р.done)
    текстЖінціП(к, 'Розуміння нагоди підтверджено.');
  else if (р.tool === 'set_weather_feel' && р.done)
    текстЖінціП(к, 'Погода: ' + (ВІДЧУТТЯ_П[р.feel] || р.feel) + '.', 'tool_weather_failed');
  else if (р.tool === 'find_item' && р.done){
    /* рядок речі — той самий, що в пари під ціною каблука (`рядокЗмінноїПари`: мініатюра, назва-посилання, крамниця ·
       ціна), у порядку, в якому код їх радить; нема жодної — карти без рядків: «нема» каже репліка */
    (р.варіанти || []).forEach(в => к.appendChild(рядокЗмінноїПари(в)));
  }
  else if (р.tool === 'switch_profile' && р.збій === 'profile_not_found')
    збійЖінціП(к, 'profile_not_found', 'tool_failed: ' + р.tool);
  else if (р.tool === 'switch_profile' && р.збій === 'profile_switch_blocked')
    збійЖінціП(к, 'profile_switch_blocked', 'tool_failed: ' + р.tool);
  else if (р.знайдено === false) збійЖінціП(к, 'scenario_not_found', 'tool_failed: ' + р.tool);
  else збійЖінціП(к, ЗБІЙ_ІНСТРУМЕНТА_П[р.tool] || 'not_written', 'tool_failed: ' + р.tool);
  return к;
}
