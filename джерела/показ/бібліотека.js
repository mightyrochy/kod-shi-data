async function відкритиСценарій(ід){
  const d = await дб();
  const з = await new Promise((рез, від)=>{ const r = d.transaction('сценарії').objectStore('сценарії').get(ід);
    r.onsuccess = ()=>рез(r.result); r.onerror = ()=>від(r.error); });
  if (!з) return false;
  застосуватиСценарій(з);
  СЦ = {ід: з.ід, назва: з.назва || '', змінено:false};
  малюватиНазвуСценарію(); показатиФормуЗбереження(false);
  await зберегтиЧернетку();
  режим('сценарій');
  малюватиБічніСценарії();
  return true;
}
