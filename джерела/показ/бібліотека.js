/* Старі ключі нормалізуються і при відновленні, і на вході картки з кешованого паспорта. */
function чиннийПаспортП(п){
  if (!п) return п;
  for (const [поле, опис] of Object.entries(ОПИС_ПОЛІВ_П)){
    if (опис.старі_ключі && поле in п) п[поле] = чиннийКлючПаспортаП(поле, п[поле]);
  }
  return п;
}
