/* Класи моделі в її порядку; інший перелік міток — інша модель, і маска значила б інше. */
const МІТКИ_СЕГМЕНТАЦІЇ_П = ['background', 'hair', 'body-skin', 'face-skin', 'clothes', 'others'];
const КЛ_П = {тло: 0, волосся: 1, тіло: 2, обличчя: 3, одяг: 4, інше: 5};
/* Вхід моделі — 256 px, тож край маски на кадрі невизначений на довга_сторона/256 px:
   шов — смуга такої ширини, щоб злам маски не лишав сходинок. */
const ВХІД_СЕГМЕНТАЦІЇ_П = 256;
/* Суміщення міряє голову на сітці з такою довгою стороною: на кадрі на повний зріст
   обличчя тоді має ~20 px заввишки — досить для частки збігу, а пошук лишається миттєвим. */
const СІТКА_СУМІЩЕННЯ_П = 512;
/* Частка збігу голови (перетин/об'єднання масок) після суміщення, нижче якої примірка
   змінила позу чи кут голови: накладання дало б два контури. Початкове значення; кожна
   примірка пише виміряний збіг у звіт (`етапи.повернення`) — поріг калібрує живе мірило. */
const МІН_ЗБІГ_ГОЛОВИ_П = 0.8;
/* Тон шкіри примірки підводиться до її тону множником на канал. Множник поза межами —
   уже не зсув тону, а інше світло чи хибний клас: тоді не підводимо (множник 1). */
const МЕЖІ_ТОНУ_П = [0.8, 1.25];
/* Менше спільної шкіри — середнє тону міряє шум стиснення, а не шкіру. */
const МІН_ШКІРИ_ТОНУ_П = 400;

/* ── Чисті функції: класи й пікселі → суміщення, маска, кадр (тест — `тест_показу.js`) ── */

const головаП = к => к === КЛ_П.волосся || к === КЛ_П.обличчя;
const шкіраП = к => к === КЛ_П.тіло || к === КЛ_П.обличчя;

/* Центр і площа голови на карті класів (центри пікселів, крок сітки `ст`). */
function моментиГоловиП(кл, ш, в, ст){
  let н = 0, сх = 0, су = 0;
  for (let у = 0; у < в; у += ст) for (let х = 0; х < ш; х += ст)
    if (головаП(кл[у * ш + х])){ н++; сх += х + 0.5; су += у + 0.5; }
  return н ? {х: сх / н, у: су / н, площа: н * ст * ст} : null;
}

/* Збіг голови (перетин/об'єднання) при відображенні її кадру в кадр примірки
   г = м·о + з (координати центрів пікселів), лічений на сітці її кадру в рамці навколо голови. */
function збігГоловиП(о, г, сум, рамка, ст){
  let пер = 0, об = 0;
  for (let у = рамка.у0; у < рамка.у1; у += ст){
    const гу = Math.floor(сум.м * (у + 0.5) + сум.зу);
    for (let х = рамка.х0; х < рамка.х1; х += ст){
      const гх = Math.floor(сум.м * (х + 0.5) + сум.зх);
      const вО = головаП(о.кл[у * о.ш + х]);
      const вГ = гх >= 0 && гу >= 0 && гх < г.ш && гу < г.в && головаП(г.кл[гу * г.ш + гх]);
      if (вО && вГ) пер++;
      if (вО || вГ) об++;
    }
  }
  return об ? пер / об : 0;
}

/* Масштаб і зсув кадру примірки відносно її фото за головою.
   Початок — моменти голови (центр і корінь площі), далі спуск по масштабу й зсуву
   з половинним кроком, доки частка збігу росте. Нема голови на одному з кадрів — null. */
function суміститиП(о, г){
  const стО = Math.max(1, Math.round(Math.max(о.ш, о.в) / СІТКА_СУМІЩЕННЯ_П));
  const стГ = Math.max(1, Math.round(Math.max(г.ш, г.в) / СІТКА_СУМІЩЕННЯ_П));
  const мО = моментиГоловиП(о.кл, о.ш, о.в, стО), мГ = моментиГоловиП(г.кл, г.ш, г.в, стГ);
  if (!мО || !мГ) return null;
  /* рамка голови її кадру з полем у розмір голови — туди влізе й зсунута голова примірки */
  const р = Math.sqrt(мО.площа);
  const рамка = {х0: Math.max(0, Math.floor(мО.х - 1.5 * р)), х1: Math.min(о.ш, Math.ceil(мО.х + 1.5 * р)),
                 у0: Math.max(0, Math.floor(мО.у - 1.5 * р)), у1: Math.min(о.в, Math.ceil(мО.у + 1.5 * р))};
  const м = Math.sqrt(мГ.площа / мО.площа);
  let сум = {м, зх: мГ.х - м * мО.х, зу: мГ.у - м * мО.у};
  let збіг = збігГоловиП(о, г, сум, рамка, стО);
  let км = 0.04 * м, кз = 4 * стГ;
  while (км > 0.001 * м || кз > 0.25){
    let краще = null;
    for (const [дм, дх, ду] of [[км, 0, 0], [-км, 0, 0], [0, кз, 0], [0, -кз, 0], [0, 0, кз], [0, 0, -кз]]){
      /* масштаб міняється навколо центру голови, щоб не зсувати її разом із ним */
      const нм = сум.м + дм;
      const н = {м: нм, зх: сум.зх - дм * мО.х + дх, зу: сум.зу - дм * мО.у + ду};
      const з = збігГоловиП(о, г, н, рамка, стО);
      if (з > збіг + 1e-9 && (!краще || з > краще.з)) краще = {н, з};
    }
    if (краще){ сум = краще.н; збіг = краще.з; }
    else { км /= 2; кз /= 2; }
  }
  return Object.assign(сум, {збіг});
}

/* Відстань кожного пікселя маски до найближчого пікселя поза нею (фаска 1/√2, два проходи).
   Край кадру — не край маски: за ним нема чого зшивати. */
function відстаньУМаскиП(К, ш, в){
  const Д = new Float32Array(ш * в), Б = 1e9, Р = Math.SQRT2;
  for (let і = 0; і < Д.length; і++) Д[і] = К[і] ? Б : 0;
  for (let у = 0; у < в; у++) for (let х = 0; х < ш; х++){
    const і = у * ш + х; if (!Д[і]) continue;
    let д = Д[і];
    if (х > 0) д = Math.min(д, Д[і - 1] + 1);
    if (у > 0){
      д = Math.min(д, Д[і - ш] + 1);
      if (х > 0) д = Math.min(д, Д[і - ш - 1] + Р);
      if (х < ш - 1) д = Math.min(д, Д[і - ш + 1] + Р);
    }
    Д[і] = д;
  }
  for (let у = в - 1; у >= 0; у--) for (let х = ш - 1; х >= 0; х--){
    const і = у * ш + х; if (!Д[і]) continue;
    let д = Д[і];
    if (х < ш - 1) д = Math.min(д, Д[і + 1] + 1);
    if (у < в - 1){
      д = Math.min(д, Д[і + ш] + 1);
      if (х < ш - 1) д = Math.min(д, Д[і + ш + 1] + Р);
      if (х > 0) д = Math.min(д, Д[і + ш - 1] + Р);
    }
    Д[і] = д;
  }
  return Д;
}

/* Кадр примірки в рамці її фото: білінійно пікселі, найближчим — класи. */
function перенестиКадрП(г, сум, рамка){
  const {ш, в} = рамка, П4 = new Uint8ClampedArray(ш * в * 4), кл = new Uint8Array(ш * в);
  for (let у = 0; у < в; у++){
    const гу = сум.м * (рамка.у + у + 0.5) + сум.зу - 0.5;
    const у0 = Math.max(0, Math.min(г.в - 1, Math.floor(гу))), у1 = Math.min(г.в - 1, у0 + 1);
    const ву = Math.max(0, Math.min(1, гу - у0));
    for (let х = 0; х < ш; х++){
      const гх = сум.м * (рамка.х + х + 0.5) + сум.зх - 0.5;
      const х0 = Math.max(0, Math.min(г.ш - 1, Math.floor(гх))), х1 = Math.min(г.ш - 1, х0 + 1);
      const вх = Math.max(0, Math.min(1, гх - х0));
      const і = у * ш + х;
      for (let к = 0; к < 4; к++){
        const а = г.пікс[(у0 * г.ш + х0) * 4 + к], б = г.пікс[(у0 * г.ш + х1) * 4 + к];
        const с = г.пікс[(у1 * г.ш + х0) * 4 + к], д = г.пікс[(у1 * г.ш + х1) * 4 + к];
        П4[і * 4 + к] = (а * (1 - вх) + б * вх) * (1 - ву) + (с * (1 - вх) + д * вх) * ву;
      }
      кл[і] = г.кл[Math.min(г.в - 1, Math.floor(гу + 0.5)) * г.ш + Math.min(г.ш - 1, Math.floor(гх + 0.5))];
    }
  }
  return {пікс: П4, кл};
}

/* Повертає її на кадр примірки.
   о, г — {пікс: RGBA, кл: класи моделі, ш, в}: її фото й кадр примірки; `змінаОбличчя` — запит
   просив макіяж, тож обличчя — область примірки. Вихід — кадр у рамці її фото, куди сягає
   кадр примірки, і звіт; не вдалось — {чому} без кадру. */
function повернутиП(о, г, змінаОбличчя){
  const сум = суміститиП(о, г);
  if (!сум) return {чому: 'no_head'};
  const звіт = {масштаб: +сум.м.toFixed(4), зсув: [+сум.зх.toFixed(1), +сум.зу.toFixed(1)],
                збіг_голови: +сум.збіг.toFixed(3), обличчя: змінаОбличчя ? 'макіяж — з примірки' : 'з фото'};
  if (сум.збіг < МІН_ЗБІГ_ГОЛОВИ_П) return Object.assign(звіт, {чому: 'head_mismatch'});
  /* рамка: пікселі її фото, чий центр падає всередину кадру примірки */
  const х = Math.max(0, Math.ceil(-сум.зх / сум.м - 0.5)), у = Math.max(0, Math.ceil(-сум.зу / сум.м - 0.5));
  const х1 = Math.min(о.ш, Math.floor((г.ш - сум.зх) / сум.м - 0.5) + 1);
  const у1 = Math.min(о.в, Math.floor((г.в - сум.зу) / сум.м - 0.5) + 1);
  if (х1 - х < 2 || у1 - у < 2) return Object.assign(звіт, {чому: 'no_overlap'});
  const рамка = {х, у, ш: х1 - х, в: у1 - у};
  const гз = перенестиКадрП(г, сум, рамка);
  const Н = рамка.ш * рамка.в;
  /* маска повернення: її тло, волосся, шкіра — поза новою річчю (одяг, аксесуар примірки) */
  const К = new Uint8Array(Н);
  let повернено = 0;
  const сума = [[0, 0, 0], [0, 0, 0]];
  let шкіри = 0;
  for (let і = 0; і < Н; і++){
    const ко = о.кл[(рамка.у + Math.floor(і / рамка.ш)) * о.ш + рамка.х + і % рамка.ш], кг = гз.кл[і];
    const лишається = ко === КЛ_П.тло || ко === КЛ_П.волосся || ко === КЛ_П.тіло
      || (ко === КЛ_П.обличчя && !змінаОбличчя);
    К[і] = (лишається && кг !== КЛ_П.одяг && кг !== КЛ_П.інше) ? 1 : 0;
    повернено += К[і];
    if (К[і] && шкіраП(ко) && шкіраП(кг)){
      const іо = ((рамка.у + Math.floor(і / рамка.ш)) * о.ш + рамка.х + і % рамка.ш) * 4;
      for (let к = 0; к < 3; к++){ сума[0][к] += о.пікс[іо + к]; сума[1][к] += гз.пікс[і * 4 + к]; }
      шкіри++;
    }
  }
  /* тон шкіри примірки — до її тону: та сама шкіра на обох кадрах дає множник на канал */
  let тон = [1, 1, 1];
  if (шкіри >= МІН_ШКІРИ_ТОНУ_П){
    const м = [0, 1, 2].map(к => сума[1][к] ? сума[0][к] / сума[1][к] : 1);
    if (м.every(в => в >= МЕЖІ_ТОНУ_П[0] && в <= МЕЖІ_ТОНУ_П[1])) тон = м;
  }
  const шов = Math.max(1, Math.ceil(Math.max(о.ш, о.в) / ВХІД_СЕГМЕНТАЦІЇ_П));
  const Д = відстаньУМаскиП(К, рамка.ш, рамка.в);
  const вих = new Uint8ClampedArray(Н * 4);
  let точно = 0;
  for (let і = 0; і < Н; і++){
    const іо = ((рамка.у + Math.floor(і / рамка.ш)) * о.ш + рамка.х + і % рамка.ш) * 4, ів = і * 4;
    const а = К[і] ? Math.min(1, Д[і] / шов) : 0;
    const підвести = шкіраП(гз.кл[і]);
    if (а === 1) точно++;
    for (let к = 0; к < 3; к++){
      const гп = підвести ? гз.пікс[ів + к] * тон[к] : гз.пікс[ів + к];
      вих[ів + к] = а === 1 ? о.пікс[іо + к] : а * о.пікс[іо + к] + (1 - а) * гп;
    }
    вих[ів + 3] = 255;
  }
  return {пікс: вих, ш: рамка.ш, в: рамка.в, звіт: Object.assign(звіт, {
    рамка: [рамка.х, рамка.у, рамка.ш, рамка.в], шов_px: шов,
    частка_поверненого: +(повернено / Н).toFixed(3), частка_точно: +(точно / Н).toFixed(3),
    тон_шкіри: тон.map(в => +в.toFixed(3)), шкіри_для_тону: шкіри})};
}

/* Кадр картки для показу: її файл чи адреса — як є; кадр генератора (`data:`) — лише той,
   що пройшов повернення (звіт повернення називає довжину саме цього кадру). Кадр, збережений
   до повернення, не показується: на ньому може бути не вона. */
function кадрПоказуП(к){
  const кадр = к && к.картинка;
  if (!кадр) return null;
  if (!/^data:/i.test(String(кадр))) return String(кадр);
  const пов = (к.етапи || {}).повернення;
  return (пов && пов.символів === String(кадр).length) ? String(кадр) : null;
}

/* ── Браузер: модель, декодування, полотно ── */

let СЕГМЕНТАТОР_П = null;
/* Тягне файл із перевіркою відбитка; відбиток не зійшовся — `fetch` відмовляє сам. */
async function файлСегментаціїП(ім){
  const [адреса, відбиток] = ФАЙЛИ_СЕГМЕНТАЦІЇ_П[ім];
  const в = await fetch(адреса, {integrity: відбиток});
  if (!в.ok) throw new Error('segmenter_http_' + в.status + ': ' + ім);
  return в.blob();
}
/* Модель піднімається раз на сторінку; збій не запам'ятовується — наступна примірка спробує знову. */
function сегментаторП(){
  if (!СЕГМЕНТАТОР_П){
    СЕГМЕНТАТОР_П = (async () => {
      const [біб, зав, wasm, мод] = await Promise.all(['бібліотека', 'завантажувач', 'wasm', 'модель']
        .map(файлСегментаціїП));
      const урл = б => URL.createObjectURL(б);
      const {ImageSegmenter} = await import(урл(new Blob([біб], {type: 'text/javascript'})));
      const с = await ImageSegmenter.createFromOptions(
        {wasmLoaderPath: урл(new Blob([зав], {type: 'text/javascript'})), wasmBinaryPath: урл(wasm)},
        {baseOptions: {modelAssetBuffer: new Uint8Array(await мод.arrayBuffer()), delegate: 'CPU'},
         runningMode: 'IMAGE', outputCategoryMask: true, outputConfidenceMasks: false});
      const мітки = с.getLabels();
      if (мітки.join() !== МІТКИ_СЕГМЕНТАЦІЇ_П.join()) throw new Error('segmenter_labels: ' + мітки.join());
      return с;
    })();
    СЕГМЕНТАТОР_П.then(null, () => { СЕГМЕНТАТОР_П = null; });
  }
  return СЕГМЕНТАТОР_П;
}
/* base64-кадр → пікселі й класи моделі тієї самої роздільності. */
async function класиКадруП(сегм, тип, дані){
  const бін = atob(дані), байти = new Uint8Array(бін.length);
  for (let і = 0; і < бін.length; і++) байти[і] = бін.charCodeAt(і);
  const бм = await createImageBitmap(new Blob([байти], {type: тип || 'image/png'}));
  const п = document.createElement('canvas'); п.width = бм.width; п.height = бм.height;
  const кт = п.getContext('2d', {willReadFrequently: true});
  кт.drawImage(бм, 0, 0);
  if (бм.close) бм.close();
  const р = сегм.segment(п);
  const м = р.categoryMask;
  if (!м || м.width !== п.width || м.height !== п.height) throw new Error('segmenter_mask_size');
  const кл = м.getAsUint8Array().slice();
  if (р.close) р.close();
  return {пікс: кт.getImageData(0, 0, п.width, п.height).data, кл, ш: п.width, в: п.height};
}
/* Її кадр сегментується, поки генератор малює: результат (чи збій) чекає на кадр примірки. */
function підготуватиПоверненняП(її){
  return сегментаторП().then(с => класиКадруП(с, її.тип, її.дані)).then(о => ({о}), е => ({е}));
}
/* Пікселі → data URI PNG: без стиснення з втратами повернені пікселі дорівнюють її фото. */
function кадрУPNGП(пікс, ш, в){
  const пол = document.createElement('canvas'); пол.width = ш; пол.height = в;
  пол.getContext('2d').putImageData(new ImageData(пікс, ш, в), 0, 0);
  return пол.toDataURL('image/png');
}
/* Повертає її на кадр примірки: {кадр, звіт} або {звіт з `чому`} без кадру. */
async function повернутиЛюдинуП(підготовка, джерело, змінаОбличчя){
  const п = await підготовка;
  if (п.е) return {звіт: {чому: 'segmenter_failed', помилка: String(п.е && п.е.message || п.е).slice(0, 200)}};
  const г = await класиКадруП(await сегментаторП(), джерело.media_type, джерело.data);
  const р = повернутиП(п.о, г, змінаОбличчя);
  if (!р.пікс) return {звіт: р};
  const кадр = кадрУPNGП(р.пікс, р.ш, р.в);
  return {кадр, звіт: Object.assign(р.звіт, {символів: кадр.length})};
}
