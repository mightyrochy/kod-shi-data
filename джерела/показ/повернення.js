/* ── ПОВЕРНЕННЯ ЛЮДИНИ НА ПРИМІРКУ ──────────────────────────────────────────
   Що на примірці та сама людина, гарантує код, а не промпт (аудит/ПРОДУКТ.md, «Примірка»):
   генератор перемальовує весь кадр — тон шкіри, плечі, фігуру, — тож після нього код
   повертає з її фото все, чого примірка не міняє. Три кроки:
   1) маски частин людини на обох кадрах — відкрита безкоштовна модель сегментації
      MediaPipe `selfie_multiclass_256x256` (Apache-2.0), у браузері: тло, волосся, шкіра
      тіла, шкіра обличчя, одяг, інше (аксесуари);
   2) суміщення кадру примірки з її фото — масштаб і зсув за головою (волосся ∪ обличчя):
      голову примірка не міняє, а силует міняє крій;
   3) накладання: піксель її фото там, де на її фото тло, волосся чи шкіра (обличчя — лише
      коли запит не просив макіяжу: макіяж міняє обличчя), а на примірці там не одяг і не
      аксесуар — тобто поза областю нової речі; решта — кадр примірки, шкіра в ньому — у тон
      її шкіри. М'який шов — смуга всередині маски шириною з похибку її краю.
   Повернути не вдалось — кадру нема: неповернений кадр показав би не її. */

