/* ПОКОЛІННЯ ВІДПОВІДІ (крок 4.1-Б-2). Виклик із `{ключ}` робить усі попередні виклики з тим самим
   ключем застарілими: їхня відповідь не віддається продовженню — проміс відхиляється помилкою з `застаріло: true`,
   і запис стану й DOM після `await` не виконується. Без ключа виклик ніщо не відміняє. Продовження, що йде ще
   й після ДРУГОГО очікування (мовна модель), бере `поколінняМістуП(ключ)` одразу після відповіді моста й звіряє
   `чиннеМістуП(ключ, пок)` перед записом. Звірка одна — тут: інші місця (`чинний()` заміни, `ж()` оцінки) звіряють
   ще й позицію картки чи виклики моделі між кроками, тож лишаються. Покоління — дія власника `стан.js` з ключем
   `'міст:' + ключ` (4.5): виклик із ключем починає нову дію, і стара перестає бути чинною. */
function поколінняМістуП(ключ){ return чиннаДіяП('міст:' + ключ); }
function чиннеМістуП(ключ, пок){ return чиннаДіяП('міст:' + ключ) === (пок || null); }
/* вхід зник без нового виклику (немає з чого рахувати): те, що ще летить, теж застаріле */
function відкинутиМістП(ключ){ скасуватиДіюП('міст:' + ключ); }
function застарілаВідповідьП(ключ){
  const е = new Error('stale_bridge_answer: ' + ключ); е.застаріло = true; return е;
}

async function містП(ім, дані, {ключ = null, першаРука = null} = {}){
  const мій = ключ != null ? почитиДіюП('міст:' + ключ) : null;
  /* Суд образу в Pyodide — 5–6 с поспіль, і сторінка не чула б дотику «Так, оцінюй» до його кінця; каталог
     на екрані «Роздивляюсь речі…» — 10–15 с: ці кроки йдуть `bridge.виклик_а`, що поступається головному
     потоку між своїми частинами; решта кроків — як були. */
  const поступливий = ім === 'оцінка' && !!дані && (дані.крок === 'суд' || дані.крок === 'каталог');
  let вих;
  try{
    вих = await транспортМостуП(ім, JSON.stringify(дані === undefined ? null : дані), поступливий, першаРука);
  }catch(е){
    /* застарілий виклик, що впав, теж мовчить: помилку старого входу жінка не читає */
    if (мій && !мій.чинна()) throw застарілаВідповідьП(ключ);
    throw е;
  }
  if (мій && !мій.чинна()) throw застарілаВідповідьП(ключ);
  return typeof вих === 'string' ? JSON.parse(вих) : вих;
}
