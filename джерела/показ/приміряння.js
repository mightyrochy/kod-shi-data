/* Пропорції ТОГО, ЩО ПРИЙШЛО. Байти вже на руках (base64 у відповіді), тож ні
   мережі, ні DOM тут не треба — лише `createImageBitmap`, той самий, яким
   `блобВБазу` міряє те, що ми ВІДПРАВИЛИ. */
async function розмір_картинки(тип, дані){
  try{
    const бін = atob(дані);
    const байти = new Uint8Array(бін.length);
    for (let i = 0; i < бін.length; i++) байти[i] = бін.charCodeAt(i);
    const бм = await createImageBitmap(new Blob([байти], {type: тип || 'image/png'}));
    const р = {ширина: бм.width, висота: бм.height};
    if (бм.close) бм.close();
    return (р.ширина > 0 && р.висота > 0) ? р : null;
  }catch(e){ console.warn('пропорції картинки не виміряні:', e); return null; }
}

