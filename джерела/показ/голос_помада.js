/* Поля сценарію змінено (плиткою, збереженим сценарієм, паспортом чи довідником): екран показує їх наново, а
   сходинку помад логіка просить, щойно колір губ видно, — той самий вхід удруге не рахується. */
function поляЗміненоП(){ показатиСценарій(); if (губиВидноП()) оновитиПомадиП(); }
/* Що екран каже про сходинку: копія відповіді ендпойнта (з реченнями мовної моделі, коли приїхали) і вид збою;
   сам збій уже в журналі збоїв (`збійЖінціП` у `оновитиПомадиП`), екран показує його шаблон. */
