    база = поле.value || '';
    сама_стала = true;
    фінальних = 0; чекаєЗапису = false;
    try{
      розп = new Клас();
    }catch(e){ розп = null; сказати(ГОЛОС_НЕМА); return; }
    const ця = поточна = {останній: база, дозволено: true};
