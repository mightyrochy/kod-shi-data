/* ── ВІДТІНКИ ПОМАДИ: СХОДИНКА З КОДУ Й ПОДІЛ ЗА R-MUA-03 ──────
   ЧОМУ НЕ НАТИВНИЙ ВИБІР. Нативний вибір кольору браузера — єдине поле
   паспорта, де кольори не приходили б з коду. Android показує вісім квадратів
   чистого RGB (червоний, ціан, синій, зелений, маджента, жовтий, чорний,
   білий); помад таких кольорів не буває, і поділу вони не дають ніякого.
   Сходинку й поділ віддає `bridge.виклик("помади")`: 20 відтінків по
   семи сім'ях, рахованих у LCh із вікон лексикону, і дві групи — «рекомендовані
   тобі» й «решта», у решті на кожен відтінок рядок причини. Другої таблиці
   кольорів тут нема за побудовою: JS не знає жодного hex помади.
   ФОРМАТ КЛЮЧА СТАЛИЙ. Обраний відтінок лягає в ті самі `сц-губи` і
   `сц-губи-обрано`, звідки `зібратиВхід` складає `сценарій.макіяж` у форматі
   `colorspace.додати_макіяж`. Нативний вибір лишається за словом «свій
   відтінок» і проходить той самий суд — але вибору не блокує ніколи. */
let ПОМАДИ_П = null;        // остання відповідь ендпойнта `помади`
let ПОМАДИ_КЛЮЧ_П = null;   // вхід, на якому вона порахована (профіль + свій колір)
let ПОМАДИ_ЗБІЙ_П = null;
function вхідПомадП(){
  const т = КОЛІР.точки || {};
  return {шкіра: т.шкіра || (КОЛІР.шкіра ? [КОЛІР.шкіра] : null),
          волосся: т.волосся || (КОЛІР.волосся ? [КОЛІР.волосся] : null),
          очі: КОЛІР.очі || null, очі_кільце: КОЛІР.кільце || null,
          портрет_вимір: КОЛІР.вимір || null,
          драп_сирий: драпЗЧатомП(),
          свій: (губиНазваноП() ? полеВипадкуП('сц-губи') : null)};
}
/* ── ЧОМУ ВІДТІНОК МЕНШ ХОДОВИЙ — РЕЧЕННЯ ПИШЕ МОВНА МОДЕЛЬ (Ч-3, п.12) ──
   `помада.суд` віддає причину КОДАМИ (повідомлення виду `lipstick_shade_note`), а не фразою:
   до 21 рядка на екрані (по одному на відтінок «решти» і один під її власним кольором).
   Речення складає той самий `повідомленнямП`, що й рядки картки, — ОДНИМ викликом на весь
   екран, поки сходинка вже намальована. Без моделі шару рядка причини нема, і це не тиша:
   намистина стоїть на місці, клікабельна, а рамку «не з рекомендованих — вибір лишається
   твій» екран пише сам сталим написом. Фрази коду сюди не підставляються ніколи. */
async function мовоюПомадиП(р){
  if (!МОДЕЛЬ_МОВИ_П || !р) return;
  const пов = {};
  Object.entries((р.поділ || {}).причини || {}).forEach(([к_, м]) => {
    if (м && м.kind) пов['відтінок.' + к_] = м; });
  if (р.свій && р.свій.причина && р.свій.причина.kind) пов['свій'] = р.свій.причина;
  if (!Object.keys(пов).length) return;
  const мп = await повідомленнямП(пов, 'lipstick');
  Object.keys((р.поділ || {}).причини || {}).forEach(к_ => {
    р.поділ.причини[к_] = мп.тексти['відтінок.' + к_] || null; });
  if ('свій' in пов) р.свій.причина = мп.тексти['свій'] || null;
}
async function оновитиПомадиП(){
  const вх = вхідПомадП(), к = JSON.stringify(вх);
  if (ПОМАДИ_КЛЮЧ_П === к && ПОМАДИ_П) return;
  ПОМАДИ_П = null; ПОМАДИ_ЗБІЙ_П = null;
  показатиПомади();
  let р = null, пок;
  try{
    р = await містП('помади', вх, {ключ: 'помади'}); пок = поколінняМістуП('помади');
    if (!р || !Array.isArray(р.сходинки)) throw new Error('lipstick_response_invalid');
  }catch(e){
    if (e && e.застаріло) return;  // новіший вхід уже рахується й намалює сам
    ПОМАДИ_ЗБІЙ_П = {вид: 'lipstick_failed', причина: e}; збійЖінціП(null, 'lipstick_failed', e);
    ПОМАДИ_КЛЮЧ_П = null; показатиПомади(); return;
  }
  ПОМАДИ_П = р; ПОМАДИ_КЛЮЧ_П = к;
  показатиПомади();
  try{ await мовоюПомадиП(р); }
  catch(e){
    if (!чиннеМістуП('помади', пок)) return;
    ПОМАДИ_ЗБІЙ_П = {вид: 'text_failed', причина: e}; збійЖінціП(null, 'text_failed', e); ПОМАДИ_КЛЮЧ_П = null;
  }
  if (р && р.сходинки && чиннеМістуП('помади', пок)) показатиПомади();
}
/* Колір губ видно для помітного і яскравого макіяжу — тоді й потрібна сходинка помад. */
