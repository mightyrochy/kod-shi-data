function новийНабірНижнім(сп){
  return new Set((сп||[]).map(x=>String(x).trim().toLowerCase()).filter(Boolean));
}
function безЧитачаП(п){
  const в = (п && п.вето_тверде) || {};
  return (в.без_читача||[]).map(x=>String(x)).filter(Boolean);
}
function малюватиМежіП(){
  const е = $('обр-межі'); if (!е) return;
  const п = ПАСПОРТ_П, сп = межіПаспорта(п), речення = [];
  if (п && п.джерело !== 'модель')
    речення.push('Стилістка не зрозуміла твоїх слів — випадок узято з плиток і чипів.');
  const нечитані = безЧитачаП(п);
  /* Т-16 (ноутбук, 25.09): рядок «не застосував» стояв у всіх трьох сценаріях, де
     відмов не було зовсім, — умова питала лише «меж нема, а слова є». Тепер він
     з'являється, лише коли стилістка ПОЧУЛА відмову (`вето`), а код її межею не тримає. */
  const почуто = !!(п && п.вето && ['типи','тканини','принти','кольори','зони']
                                     .some(к => (п.вето[к] || []).length));
  if (сп.length) речення.push('Твої межі враховано: ' + сп.join(', ') + '.');
  else if (почуто && !нечитані.length)
    речення.push('Твої слова передано стилістці, але твердою межею цього разу вони не стали.');
  /* ЧЕСНО ПРО СЛОВО, ЯКОГО КОД НЕ ЧИТАЄ (рядок 171): воно не зникає — стилістка
     бачить його в брифі й складає образ із ним, — але «враховано» про нього не
     кажемо, бо з пулу воно не зняло нічого. */
  if (нечитані.length)
    речення.push('Передано стилістці, але твердою межею ці слова не стали: ' + нечитані.join(', ') + '.');
  е.textContent = речення.join(' ');
  е.style.display = речення.length ? 'block' : 'none';
}
/* ШМАТКИ ВИПАДКУ З КЛЮЧАМИ ПОЛІВ — ДЖЕРЕЛО І ДЛЯ ШАПКИ, І ДЛЯ РЯДКА (Л-9,
   27.09.2026). Розвилка та сама, що була у `випадокРядком`: спершу шматки з
   паспорта (їх склав `паспорт_нагоди.паспорт_шматками_людині`), далі — старий
   запис, що несе лише рядок, і нарешті гілка БЕЗ чату, де випадок збирається з
   плиток екрана. Ключ кожного шматка — імʼя поля паспорта, те саме в обох
   гілках, тож піктограму вибирає поле, а не позиція. */
function випадокШматками(){
  if (ВИПАДОК_ШМАТКИ_П && ВИПАДОК_ШМАТКИ_П.length) return шматкиВипадкуП(ВИПАДОК_ШМАТКИ_П);
  /* РЯДОК МОДЕЛІ (`випадок`, `паспорт_рядком`) ЖІНЦІ НЕ ЙДЕ (рядок 5422, п.12): це випадок кодами (JSON, рядок
     5905) для моделей і звіту власника, і шапка з порожніми шматками показувала б його. Без шматків і рядка людині —
     плитки екрана, як у гілці без чату. */
  if (ВИПАДОК_ЛЮДИНІ_П) return шматкиВипадкуП(ВИПАДОК_ЛЮДИНІ_П);
  const н = знайти(ДОВІДНИК.нагоди, $('сц-нагода').value);
  const м = знайти(ДОВІДНИК.місця, чиннеМісце());
  const слова = словаЛюдиниП();
  /* Гілка БЕЗ чату — той самий гейт, що в `паспорт_рядком_людині` (В-2): шапка над
     картками не називає години й градусів, яких рука не ставила. Вони лишаються на
     своєму місці — у плитці й на картці сценарію, сірим. */
  const г = ТИПОВІ_НЕ_РУКОЮ_П.has('сц-година') ? NaN : parseInt($('сц-година').value);
  const т = ТИПОВІ_НЕ_РУКОЮ_П.has('сц-темп') ? NaN : parseFloat($('сц-темп').value);
  /* `слова` — її вільний текст, а не ключ довідника: ключ шматка інший (`подія`),
     і знака місця на ньому нема, як і на нагоді. */
  return [н ? {текст: н.підпис, ключ: 'нагода'}
            : (слова ? {текст: слова.replace(/\s+/g, ' ').slice(0, 60), ключ: 'подія'} : null),
          словаМісцяП(м) ? {текст: словаМісцяП(м).toLowerCase(), ключ: 'місце'} : null,
          isFinite(г) ? {текст: годинаТекстомП(г), ключ: 'година'} : null,
          isFinite(т) ? {текст: т + ' °C', ключ: 'темп_c'} : null]
         .filter(Boolean).map(ш=>({текст: ш.текст, ключ: ш.ключ, код: null}));
}
function випадокРядком(){
  /* РЯДОК, А НЕ МАСИВ (23.09.2026, рядок 147). Тут стояло
     `return [ВИПАДОК_ПАСПОРТА_П, null, null, null]` — масив, який `String()` у
     `малюватиРядокВипадку` і в `типоваНазваСценарію` перетворював на
     «…Настрій: зібрано,,,»: три порожні місця дописували три коми. Той самий
     масив їхав у `П.випадок_рядок`, у запис збереженого сценарію і в назву
     сценарію. Тепер обидві гілки повертають РЯДОК, і обидві — словами людини:
     гілка паспорта бере `випадок_людині` з коду, гілка без чату — довідник
     екрана, як доти. Старий запис без `випадок_людині` (чернетка, збережена до
     цієї правки) лишається читним: тоді береться рядок моделі, як і був.
     Л-9 (27.09.2026): склад рядка переїхав у `випадокШматками` — тут те саме,
     зшите « · », тож назва сценарію, журнал і записи не змінились ні на знак. */
  return випадокШматками().map(ш=>ш.текст).join(' · ');
}

function байтиВБ64урл(м){
  let б=''; const шм=0x8000;
  for (let i=0;i<м.length;i+=шм) б += String.fromCharCode.apply(null, м.subarray(i,i+шм));
  return btoa(б).replace(/\+/g,'-').replace(/\//g,'_').replace(/=+$/,'');
}
async function запакувати(об){
  const байти = new TextEncoder().encode(JSON.stringify(об));
  if (typeof CompressionStream === 'function'){
    try{
      const ст = new Uint8Array(await new Response(
        new Blob([байти]).stream().pipeThrough(new CompressionStream('gzip'))).arrayBuffer());
      return байтиВБ64урл(ст);
    }catch(e){}
  }
  return байтиВБ64урл(байти);
}
function копіювати(текст){
  try{
    const т=document.createElement('textarea'); т.value=текст; т.setAttribute('readonly','');
    т.style.cssText='position:fixed;top:0;left:0;width:1px;height:1px;opacity:0';
    document.body.appendChild(т); т.focus(); т.select();
    try{ т.setSelectionRange(0,текст.length); }catch(_){}
    const ок=document.execCommand('copy'); document.body.removeChild(т);
    return ок;
  }catch(e){ return false; }
}
