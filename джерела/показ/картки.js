/* ЛІЧИЛЬНИК: M — картки, які є що судити (впала рука не рахується), N — з них ті, що мають вердикт жінки. Живе в
   стані `В` (`записано` ставить `записати` після запису у сховище; `відновитиСтанКарткиП` — після повторного
   відкриття прогону з бібліотеки). */
function лічбаВердиктівП(){
  const кк = (П && П.картки) || [];
  let з = 0, оцінено = 0;
  кк.forEach((к, j) => { if (!к || к.збій) return; з++; if (В[j] && В[j].записано) оцінено++; });
  return {з, оцінено};
}
