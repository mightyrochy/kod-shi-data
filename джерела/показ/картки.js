/* наступна НЕОЦІНЕНА картка по колу після `поз` (оцінені й впалі пропускаються); `null` — неоцінених нема */
function наступнаНеоціненаП(поз){
  const кк = (П && П.картки) || [], н = кк.length;
  for (let к = 1; к < н; к++){
    const j = (поз + к) % н;
    if (кк[j] && !кк[j].збій && !(В[j] && В[j].записано)) return j;
  }
  return null;
}
