let ПРОГІН_ЗБИРАЄТЬСЯ_П = null;   // запис прогону, чиї руки ще йдуть; null — таких нема
function створитиЗаписПрогонуП(поля, картки){
  const запис = Object.assign({}, поля, {картки: (картки || []).filter(Boolean)});
  ПРОГІН_ЗБИРАЄТЬСЯ_П = запис;
  return запис;
}
/* Шов: руки, яких у записі ще нема, стають у кінець (порядок `картки` — порядок ключа), і підсумкові поля — у запис
   прогону `ід`. Картки, що вже стоять, лишаються на своїх місцях і тими самими об'єктами. Повертає {запис, було} —
   `було` карток стояло до шва; запису з таким ідом нема — null. Після шва прогін уже не збирається. */
function дописатиРукиПрогонуП(ід, картки, поля){
  const запис = ПРОГІН_ЗБИРАЄТЬСЯ_П;
  if (!запис || ід == null || String(запис.прогін) !== String(ід)) return null;
  ПРОГІН_ЗБИРАЄТЬСЯ_П = null;
  const було = запис.картки.length;
  for (const к of (картки || [])) if (к && !запис.картки.includes(к)) запис.картки.push(к);
  Object.assign(запис, поля || {});
  return {запис, було};
}
/* Збирання скінчилось без шва (виняток посеред рук): запис лишається, яким є, руки вже не йдуть. Збирання одне за
   раз (`ЗБИРАННЯ_ЗАЙНЯТО_П`), тож іда не треба; true — запис іще чекав рук. */
function закінчитиЗбиранняПрогонуП(){
  if (!ПРОГІН_ЗБИРАЄТЬСЯ_П) return false;
  ПРОГІН_ЗБИРАЄТЬСЯ_П = null;
  return true;
}
function рукиПрогонуЩеЙдутьП(ід){
  return !!ПРОГІН_ЗБИРАЄТЬСЯ_П && ід != null && String(ПРОГІН_ЗБИРАЄТЬСЯ_П.прогін) === String(ід);
}
/* Запис сховища — на показ: прогін, чиї руки ще йдуть, — той самий об'єкт, що збирання; решта — копія запису. */
function записПрогонуДляПоказуП(збережений){
  const п = (збережений || {}).П || {};
  if (рукиПрогонуЩеЙдутьП(п.прогін)) return ПРОГІН_ЗБИРАЄТЬСЯ_П;
  const копія = JSON.parse(JSON.stringify(п));
  копія.випадок_рядок = збережений.випадок || копія.випадок_рядок || '';
  return копія;
}
