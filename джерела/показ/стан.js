/* ── ВЛАСНИК СТАНУ ДІЇ (4.5, корінь Р10) ─────────────────────────────────
   Дія, що пише стан після очікувань (заміна речі, хід розмови, міст, ланцюг оцінки), бере тут номер і ключ свого
   предмета (картка, `'сценарій'`, `'чат'`, `'міст:' + ключ`, перелік речей). Нова дія того самого ключа скасовує
   стару. Перед кожним записом після `await` дія звіряє `чинна()`; запис, який треба зняти при скасуванні, кладе свій
   відкат (`відкат(ф)`), і `скасувати()` виконує відкати в зворотному порядку й обриває `аборт` — скасована дія не лишає
   записаного. `зафіксувати()` — записане стало станом (картка вже перемальована): далі скасування лише зупиняє.
   `завершити(деталі)` знімає дію з ключа й, коли дія названа, дає той самий сигнал ядра з її номером. */
let НОМЕР_ДІЇ_П = 0;
const ДІЇ_П = new Map();
function почитиДіюП(ключ, назва){
  const стара = ДІЇ_П.get(ключ);
  if (стара) стара.скасувати();
  const дія = {ключ, назва: назва || null, номер: ++НОМЕР_ДІЇ_П, стан: 'іде', аборт: new AbortController()};
  const відкати = [], умови = [];
  const зняти = () => { if (ДІЇ_П.get(ключ) === дія) ДІЇ_П.delete(ключ); };
  дія.чинна = () => дія.стан === 'іде' && ДІЇ_П.get(ключ) === дія && умови.every(у => у());
  дія.умова = у => { умови.push(у); return дія; };
  дія.відкат = ф => { if (дія.стан === 'іде') відкати.push(ф); };
  дія.зафіксувати = () => { відкати.length = 0; };
  дія.скасувати = () => {
    if (дія.стан !== 'іде') return false;
    дія.стан = 'скасовано'; зняти();
    try { дія.аборт.abort(); } catch(_){}
    for (const ф of відкати.splice(0).reverse()){ try { ф(); } catch(e){ console.error(e); } }
    return true;
  };
  дія.завершити = деталі => {
    if (дія.стан !== 'іде') return false;
    дія.стан = 'завершено'; відкати.length = 0; зняти();
    if (дія.назва) завершитиДіюЯдра(дія.назва, деталі, дія.номер);
    return true;
  };
  ДІЇ_П.set(ключ, дія);
  return дія;
}
function чиннаДіяП(ключ){ return ДІЇ_П.get(ключ) || null; }
function скасуватиДіюП(ключ){ const д = ДІЇ_П.get(ключ); return !!(д && д.скасувати()); }
