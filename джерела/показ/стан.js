function ідПакетаП(х){
  let г = 0x811c9dc5, т = String(х || '');
  for (let i = 0; i < т.length; i++){ г ^= т.charCodeAt(i); г = Math.imul(г, 0x01000193) >>> 0; }
  return 'пр-' + г.toString(36) + т.length.toString(36);
}

