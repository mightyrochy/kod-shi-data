function б64урлВБайти(s){
  s = s.replace(/-/g,'+').replace(/_/g,'/');
  while (s.length % 4) s += '=';
  const бін = atob(s), м = new Uint8Array(бін.length);
  for (let i=0;i<бін.length;i++) м[i]=бін.charCodeAt(i);
  return м;
}
async function розпакувати(х){
  /* gzip чи сирий base64url — розрізняємо за магією gzip (1f 8b) */
  const байти = б64урлВБайти(х);
  const gzip = байти.length > 2 && байти[0] === 0x1f && байти[1] === 0x8b;
  const текст = gzip
    ? await new Response(new Blob([байти]).stream().pipeThrough(new DecompressionStream('gzip'))).text()
    : new TextDecoder().decode(байти);
  const п = JSON.parse(текст);
  п._кодування = gzip ? 'gzip' : 'без стиснення';
  return п;
}

