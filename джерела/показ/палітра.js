const ВИБІР_СТИЛІСТКИ_П = {ключ: null, обіцянка: null, р: null, за_промптом: null};
function вхідСтилісткиП(){
  const в = вхідМостаП(true);
  const о = {};
  /* `каталог` і `кеш_кольорів`: кольорова основа переліку несе, скільки одягу
     нагоди лежить у її вікні (`вибір_палітри.з_одягом`) — стилістка бачить це до вибору */
  for (const к of ['шкіра','волосся','очі','очі_кільце','зріст','обхвати','аксесуарні','вимоги','намір',
                   'паспорт','гілка','схема','вибір_кольору','драп_сирий','сценарій','випадок','вето',
                   'каталог','кеш_кольорів'])
    if (в[к] !== undefined) о[к] = в[к];
  return о;
}
function злитиСтилісткуП(пал, вс){
  /* Прийнятий вибір стилістки поверх ЇЇ вибору: лише ті частини, які вона лишила, і лише ті, що
     обрала стилістка («код» — ранг коду: такого вибору не шлемо, міст сам бере ранг і каже це). */
  if (!вс || вс.нічого || !вс.вибір) return null;
  const обр = вс.вибір.обрала || {}, її = (пал && пал.вибір_кольору) || {}, ст = вс.вибір.вибір_кольору || {};
  /* частини й «хто обрав» приходять кодами: scheme|base|saturation → her|stylist|code_rank */
  const схема = (пал && пал.гілка == null && !пал.схема && обр.scheme === 'stylist') ? вс.вибір.схема : null;
  const вк = Object.assign({}, її);
  if (!її.база && обр.base === 'stylist' && ст.база)
    Object.assign(вк, {база: ст.база, база_hex: ст.база_hex, база_тип: ст.база_тип, база_стилістки: true});
  if (!її.насиченість && обр.saturation === 'stylist' && ст.насиченість) вк.насиченість = ст.насиченість;
  return {схема, вибір_кольору: Object.keys(вк).length ? вк : null,
          запис: {вибір: вс.вибір, знахідки: вс.знахідки || [], відхилено: вс.відхилено || [],
                  без_моделі: (вс.без_моделі == null ? null : вс.без_моделі)}};
}
/* Прибирає останню основу найчисленнішої сім'ї, як кандидатів пулу руки.
   Кожна сім'я, усі схеми й зафіксований нею вибір лишаються доступними. */
function скоротитиОсновиП(дані){
  const основи = дані.bases;
  if (!Array.isArray(основи)) return null;
  const групи = new Map(), сімя = о => [о.family, о.temperature, о.saturation].join('|');
  основи.forEach(о => групи.set(сімя(о), (групи.get(сімя(о)) || 0) + 1));
  const обрана = ((дані.fixed || {}).base || {}).id;
  let індекс = -1, найбільше = 1;
  for (let і = основи.length - 1; і >= 0; і--){
    const о = основи[і], кількість = групи.get(сімя(о));
    if (кількість > найбільше && о.id !== обрана){ індекс = і; найбільше = кількість; }
  }
  if (індекс < 0) return null;
  основи.splice(індекс, 1);
  return 'палітра_основи:1';
}
