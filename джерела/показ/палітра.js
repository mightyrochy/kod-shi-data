/* Стан вибору стилістки для ПОТОЧНОГО її входу: «обрала» (є результат), «обирає» (виклик іде),
   «чекає» (ще не питали). Результат іншого входу — не її вибір для цього екрана. */
function стилісткаПалітриП(){
  const ключ = JSON.stringify(вхідСтилісткиП());
  if (ВИБІР_СТИЛІСТКИ_П.ключ !== ключ) return {стан: 'чекає', р: null};
  if (ВИБІР_СТИЛІСТКИ_П.р) return {стан: ВИБІР_СТИЛІСТКИ_П.р.нічого ? 'нічого' : 'обрала', р: ВИБІР_СТИЛІСТКИ_П.р};
  return {стан: ВИБІР_СТИЛІСТКИ_П.обіцянка ? 'обирає' : 'чекає', р: null};
}
/* Рядки службового діагнозу про вибір стилістки — у звіт власника, не жінці. */
function рядкиВиборуСтилісткиП(р){
  if (!р || р.нічого || !р.вибір) return [];
  const в = р.вибір, о = в.обрала || {}, пр = в.причини || {};
  /* `обрала`/`причини` приходять кодами (`scheme`/`base`/`saturation` →
     `her`|`stylist`|`code_rank`), тож перекладати тут уже нема чого. */
  const хто = ч => String(о[ч] || 'unknown');
  const рядки = ['palette · choice · scheme=' + String(в.схема || 'unknown') + ' · scheme_by=' + хто('scheme')
    + ' · scheme_rank=' + (в.ранг_схеми ?? 'unknown') + (в.схема_рідша ? ' · scheme_rare=yes' : '')
    + (пр.scheme && пр.scheme.length ? ' · scheme_why=' + пр.scheme.join(',') : '')
    + ' · base=' + ((в.вибір_кольору || {}).база ? String(в.вибір_кольору.база).split('\u00b7')[0] : 'unknown')
    + ' · base_by=' + хто('base') + (в.основа_ранг ? ' · base_rank=' + в.основа_ранг : '')
    + (пр.base && пр.base.length ? ' · base_why=' + пр.base.join(',') : '')
    + ' · gamut=' + (в.гама || 'unknown') + ' · gamut_by=' + хто('saturation')];
  if (р.без_моделі) рядки.push('palette · choice · stylist_did_not_choose=' + р.без_моделі);
  (р.відхилено || []).forEach(х => рядки.push('palette · choice · rejected=' + х));
  /* ЗНАХІДКА — СВОЇМИ ЧИСЛАМИ, А НЕ ПЕРЕКАЗОМ `суть`: `діагностика` несе
     ті самі факти кодами (`scheme_rank`, `of_schemes`, `advised`, `reasons`), а
     українське речення `суть` лишається в самій знахідці звіту власника (П-6). */
  (р.знахідки || []).forEach(з => рядки.push('palette · choice · finding=' + з.правило + ' · register=' + з.регістр
    + ' · force_np=' + з.сила_нп
    + Object.entries(з.діагностика || {}).map(([к, v]) => ' · ' + к + '='
        + (Array.isArray(v) ? (v.join(',') || 'none') : String(v))).join('')));
  return рядки;
}

