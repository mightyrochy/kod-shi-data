function хешПакета(){
  let х = location.hash.slice(1);
  /* мітка ASCII, хвіст декодується перед порівнянням (браузер відсоткує кирилицю) */
  try{ х = decodeURIComponent(х); }catch(e){}
  /* ХЕШ ІЗ ПАРАМЕТРАМИ — НЕ ПАКЕТ: пакетом є лише base64url без винятків */
  if (х && !/^[A-Za-z0-9_-]+$/.test(х)) х = '';
  /* короткий голий хеш — токен (див. розібратиХеш), пакет образу завжди довший */
  if (х && х.length <= 48) х = '';
  return х;
}

