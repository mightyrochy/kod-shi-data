/* ЧОГО БРАКУЄ ДЛЯ ЗБИРАННЯ — одна функція на обидва шляхи. `bridge.запити`
   кидає ValueError на будь-якому відсутньому обхваті, тож перевіряємо тут,
   до виклику моделі, і кажемо словами. */
function чогоБракує(){
  const бракує = [];
  if (!КОЛІР.шкіра || !КОЛІР.волосся || !КОЛІР.очі) бракує.push('свої кольори');
  /* ── ЗРІСТ ТУТ НАРІВНІ З ОБХВАТАМИ ───────────
     Поле порожнє, поки жінка його не заповнить, і стоїть у переліку «без чого
     не зібрати» — там-таки, де `немаМірок` його тримає: інакше число за замовчуванням
     подавалося б як її вимір (`profile.масштаб` веде з нього масштаб принту,
     `посадка.тіло` — геометрію). Нічого не замикається (п.9): це та сама одна
     дія, що й чотири обхвати поруч. */
  const нм = [['мр-зріст','зріст'],['мр-плечі','плечі'],['мр-груди','груди'],
              ['мр-талія','талія'],['мр-стегна','стегна']]
    .filter(([і])=>!parseFloat($(і).value)).map(([,н])=>н);
  if (нм.length) бракує.push('обхвати: ' + нм.join(', '));
  /* ВИПАДОК МОЖЕ ПРИЙТИ ТРЬОМА ШЛЯХАМИ, І ВСІ ТРИ ЗАКОННІ (Т-08 крок 6): плитка,
     слова в розмові зі ші і ПАСПОРТ. `подія` тут нарівні з `нагода`: ключа під
     її подію в довіднику може не бути, а подія є. Окремого поля «своїми словами»
     з v4 нема — слова живуть у розмові (`словаЛюдиниП`). */
  if (!єВипадокП()) бракує.push('нагоду або опис своїми словами');
  return бракує;
}
