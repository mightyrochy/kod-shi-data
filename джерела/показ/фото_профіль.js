/* ── фото-профіль: портрет + повний зріст, живуть у IndexedDB пристрою ──── */
function читатиКв(ключ){
  return дб().then(d=>new Promise((рез,від)=>{
    const r = d.transaction('кв').objectStore('кв').get(ключ);
    r.onsuccess=()=>рез(r.result); r.onerror=()=>від(r.error);
  }));
}
/* ЩО ЛЕЖИТЬ У СЛОТАХ. Самі знімки — у сховищі під ключем профілю; у пам'яті — лише стан кожного слота: 'є' (знімок),
   'старе' (запис старого формату — рядок: показати нічим, прибрати можна), 'нема', 'збій' (сховище не прочиталось;
   причина — `причинаЗбоюФотоП`). `оновитиФотоП` перечитує сховище й каже екранові; слоти, крок «Що тобі до лиця»
   й мініатюри огляду малює екран (`екран/фото.js`, `екран/драп.js`, `екран/профіль.js`) зі зрізу `фото`. */
const СТАН_ФОТО_П = {портрет: 'нема', зріст: 'нема'}, ЗБІЙ_ФОТО_П = {портрет: null, зріст: null};
const причинаЗбоюФотоП = вид => ЗБІЙ_ФОТО_П[вид];
async function оновитиФотоП(){
  for (const вид of ['портрет', 'зріст']){
    try{
      const б = await читатиКв(ключФото(вид));
      СТАН_ФОТО_П[вид] = !б ? 'нема' : typeof б === 'string' ? 'старе' : 'є'; ЗБІЙ_ФОТО_П[вид] = null;
      ФОТО_Є[вид] = СТАН_ФОТО_П[вид] === 'є';
    }catch(e){ СТАН_ФОТО_П[вид] = 'збій'; ЗБІЙ_ФОТО_П[вид] = e || new Error('photo_read_failed'); }
  }
  ЗМІНА_ФОТО_П++;
  показатиПрофіль();
}
async function зберегтиФотоП(вид, файл){
  if (!файл) return;
  try{
    const d = await дб();
    await tx(d,'кв','readwrite', s=>s.put(файл, ключФото(вид)));
  }catch(err){ збійЖінціП($('збій-стан'), 'not_saved', err); return; }
  if (вид === 'портрет') скинутиВідповідьКольоруП();
  await оновитиФотоП();
  /* КОЛЬОРИ ЧИТАЮТЬСЯ САМІ, ЩОЙНО Є ПОРТРЕТ (v4.2): окрема кнопка «Зчитати»
     була кроком, якого людина не чекала й пропускала. Кнопка лишається —
     щоб зчитати ще раз або коли мосту нема й треба йти іншим шляхом. */
  if (вид === 'портрет' && !мостуНемаП()) зчитатиКольориЗПортрета();
}
async function прибратиФотоП(вид){
  const d = await дб();
  await tx(d,'кв','readwrite', s=>s.delete(ключФото(вид)));
  if (вид === 'портрет') скинутиВідповідьКольоруП();
  await оновитиФотоП();
}

