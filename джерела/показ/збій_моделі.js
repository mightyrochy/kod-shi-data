/* ── ЗБІЙ МОДЕЛІ — ОДИН ШЛЯХ ВІД МОСТУ ДО ЖІНКИ (наряд «Модель-збої-один-шлях») ─────────────────────────────────────
   ЩО БУЛО. Збій виклику моделі (402 — кредити, 504 — стеля часу, 400 — вхід, обрив мережі) кожне місце виклику
   розбирало саме: чат писав «Не змогла відповісти», примірка — «Приміряння не вдалось. Спробуй ще раз.», проза картки —
   «відповідь не вдалось прочитати», а шаблон про кредити кожне місце вмикало своєю латкою (#4407 — чат і повідомлення
   картки, перевірка — проза картки 16798 й оцінка з фото 16799, #4482 — примірка 16834): та сама вада вчетверте. На
   скінчені кредити жінка діставала пораду повторити, яка не допоможе й може коштувати ще виклик, а 504 повторювався
   двічі — ще два платні виклики (16748, 16806).
   ЩО ТЕПЕР. Вид збою, повтор, шаблон для жінки й запис у журнал збоїв вирішує цей модуль, і лише він:
   · `видЗбоюМоделіП(статус, тіло)` — вид за відповіддю мосту (таблиця `ВИДИ_ЗБОЮ_МОДЕЛІ_П`);
   · `повторЗбоюМоделіП` — чи повторювати спробу й коли (кличе лише планувальник `плануватиВикликП`);
   · `збійМоделіЗВідповідіП`, `збійМоделіЗВинятку` — виняток `ЗбійМоделіП` з видом (кидає лише планувальник: місця
     виклику дістають або відповідь, або цей виняток);
   · `шаблонЗбоюМоделіП(причина)` — ключ шаблону `ШАБЛОНИ_ЗБОЮ_П` для виду; `збійЖінціП` бере його замість шаблону
     місця, тож місце виклику передає лише свій вид («що не вдалось») — яким словом сказати про збій моделі, воно не
     вирішує й про коди HTTP не знає;
   · `збійЗупиняєЗапаснийП` — чи збій моделі шару закриває запасний виклик шляхом main (той самий вид упав би й там).
   Кредити (402) — один виклик: після першої такої відповіді `КРЕДИТИ_ДО_П` зачиняє виклики на `КРЕДИТИ_ПАУЗА_МС`, і
   кожен наступний виклик, зокрема вже поставлений у чергу, падає тим самим видом без мережі. Збій, що не з транспорту
   (обрізана відповідь, кадри не дійшли, формат), — не цей модуль: його шаблон лишається шаблоном місця. */
const ВИДИ_ЗБОЮ_МОДЕЛІ_П = {
  /* повторів — скільки разів планувальник повторює спробу; шаблон — ключ `ШАБЛОНИ_ЗБОЮ_П` */
  'кредити':        {повторів: 0, шаблон: 'credits_exhausted'},       // 402 `credits_exhausted` мосту
  'ліміт_доби':     {повторів: 0, шаблон: 'model_daily_limit'},       // 429 мосту: добова межа токена
  'перевантаження': {повторів: 2, шаблон: 'model_busy'},              // 429 / 503 провайдера — сплеск минає
  'час':            {повторів: 1, шаблон: 'model_timeout'},           // 502 / 504 / 524 — стеля часу дороги чи моделі
  'вхід':           {повторів: 0, шаблон: 'model_input_rejected'},    // 400 / 413 / 422 — той самий вхід дасть те саме
  'мережа':         {повторів: 1, шаблон: 'model_network'},           // обрив (599, TypeError fetch) — лише швидкий
  'доступ':         {повторів: 0, шаблон: 'model_access'},            // 401 / 403 — токен чи походження
  'інше':           {повторів: 0, шаблон: 'model_unavailable'},
};
const ЗАТРИМКИ_ПОВТОРУ_П = [20000, 60000];
const ОБРИВ_ШВИДКИЙ_МС = 30000;
const КРЕДИТИ_ПАУЗА_МС = 30 * 60 * 1000;
let КРЕДИТИ_ДО_П = 0;
class ЗбійМоделіП extends Error {
  constructor(вид, статус, повідомлення, без_виклику){
    super(повідомлення);
    this.name = 'ЗбійМоделіП'; this.вид = вид; this.статус = статус;
    if (без_виклику) this.без_виклику = true;
  }
}
function видЗбоюМоделіП(статус, тіло){
  const т = String(тіло || '');
  if (статус === 402 || /credits_exhausted/.test(т)) return 'кредити';
  if (статус === 429 && /добова межа/.test(т)) return 'ліміт_доби';
  if (статус === 429 || статус === 503) return 'перевантаження';
  if ([502, 504, 524].includes(статус)) return 'час';
  if ([400, 413, 422].includes(статус)) return 'вхід';
  if (статус === 599) return 'мережа';
  if (статус === 401 || статус === 403) return 'доступ';
  return 'інше';
}
/* Вид збою з будь-якої причини: виняток модуля — його вид; виняток старого вигляду з текстом мосту (`… http=402 …
   credits_exhausted`, `TypeError: Failed to fetch`) — за тим самим правилом; решта — null (не збій транспорту). */
function видЗбоюЗПричиниП(причина){
  if (!причина) return null;
  if (причина instanceof ЗбійМоделіП) return причина.вид;
  if (причина instanceof TypeError && /fetch|network|load failed/i.test(String(причина.message || ''))) return 'мережа';
  const т = String(причина.message || причина);
  if (/credits_exhausted/.test(т)) return 'кредити';
  const м = /model · http=(\d{3})\b/.exec(т);
  return м ? видЗбоюМоделіП(Number(м[1]), т) : null;
}
function шаблонЗбоюМоделіП(причина){
  const вид = видЗбоюЗПричиниП(причина);
  return вид ? ВИДИ_ЗБОЮ_МОДЕЛІ_П[вид].шаблон : null;
}
/* Чи повторювати спробу: → {причина, мс} або null. `з` — запис спроби (модель, старт, кінець), `було` — лічба повторів
   цього виклику за видом. Обрив сторінкою (AbortError) не повторюється ніколи; обрив мережі — лише швидкий (так рветься
   з'єднання, якого сервер не взяв); обрив після довгого виклику — таймаут дороги, повтор лише подвоїв би чекання.
   Модель зображень (`gpt-image-`) на стелю часу не повторюється зовсім: виклик міг дійти до OpenAI й бути оплаченим. */
function повторЗбоюМоделіП(з, вид, статус, сигнал, помилка, було){
  if ((сигнал && сигнал.aborted) || (помилка && помилка.name === 'AbortError') || !вид) return null;
  const к = було[вид] || 0;
  if (к >= ВИДИ_ЗБОЮ_МОДЕЛІ_П[вид].повторів) return null;
  if (вид === 'мережа' && з.кінець - (з.старт == null ? з.кінець : з.старт) > ОБРИВ_ШВИДКИЙ_МС) return null;
  if (вид === 'час' && /^gpt-image-/i.test(String(з.модель || ''))) return null;
  було[вид] = к + 1;
  if (вид === 'мережа') return {причина: 'connection_reset', мс: 2000 + Math.random()*2000};
  return {причина: 'http_' + статус,
          мс: (статус === 503 ? ЗАТРИМКИ_ПОВТОРУ_П[к] / 2 : ЗАТРИМКИ_ПОВТОРУ_П[к]) + Math.random()*4000};
}
/* Кредити зачинено: виклик не йде в мережу (і з черги теж) — той самий вид, без нового 402 мосту. */
function кредитиЗачиненоП(){
  if (Date.now() >= КРЕДИТИ_ДО_П) return null;
  return new ЗбійМоделіП('кредити', 402, 'model · http=402 · credits_exhausted · no_call: bridge answered 402 at '
                         + new Date(КРЕДИТИ_ДО_П - КРЕДИТИ_ПАУЗА_МС).toISOString(), true);
}
/* Не-ok відповідь мосту → виняток модуля. Текст — той самий, що доти (`model · http=… · <межі> · body=…`): його читають
   звіт власника й записи ходу. 402 зачиняє кредити для всієї сторінки. */
function збійМоделіЗВідповідіП(відп, тіло){
  const вид = видЗбоюМоделіП(відп.status, тіло);
  if (вид === 'кредити') КРЕДИТИ_ДО_П = Date.now() + КРЕДИТИ_ПАУЗА_МС;
  return new ЗбійМоделіП(вид, відп.status, 'model · http=' + відп.status + ' · ' + _межіП(відп) + ' · body=' + тіло);
}
/* Обрив мережі після вичерпаних повторів — той самий вид, що й 599 (текст винятку браузера — у повідомленні). */
function збійМоделіЗВинятку(e){
  if (e instanceof ЗбійМоделіП || !(e instanceof TypeError)) return e;
  return new ЗбійМоделіП('мережа', 599, 'model · http=599 · network · ' + String(e.message || e).slice(0, 200));
}
/* Збій моделі шару, після якого запасний виклик (шлях main) лише коштує ще виклик і падає тим самим видом: кредити, ліміт
   доби й доступ спільні для всіх моделей моста, а коли модель шару — та сама, що main, будь-який збій моделі повториться і
   там. → виняток модуля (місце кидає його до свого кінцевого шаблону) або null (запасний шлях лишається). */
function збійЗупиняєЗапаснийП(причина, модельШару){
  const вид = видЗбоюЗПричиниП(причина);
  if (!вид || (!['кредити', 'ліміт_доби', 'доступ'].includes(вид) && модельШару !== МОДЕЛЬ_П)) return null;
  if (причина instanceof ЗбійМоделіП) return причина;
  const т = String((причина && причина.message) || причина).replace(/^layer_failed: /, '');
  const м = /model · http=(\d{3})\b/.exec(т);
  return new ЗбійМоделіП(вид, м ? Number(м[1]) : 0, т);
}
