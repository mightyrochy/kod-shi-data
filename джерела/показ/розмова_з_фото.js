async function допитОцінкиП(){
  const поле = $('оц-допит-поле'), ст = $('оц-допит-стан'), кн = $('оц-допит-слати'), р = ОЦ.результат;
  const слова = String((поле && поле.value) || '').trim();
  if (!слова || !р || ОЦ.іде) return;
  ОЦ.іде = true; if (кн) кн.disabled = true;
  const х = {питання: слова, коли: new Date().toISOString(), мова_шару: []};
  р.допит.push(х);
  const стр = $('оц-допит-стрічка'); if (стр) стр.appendChild(їїСловаЕлП('div', 'репліка вона', слова));
  if (поле) поле.value = '';
  try{
    ст.textContent = 'Думаю…';
    let питання = {free_text: слова, lang: 'uk'};
    if (МОДЕЛЬ_МОВИ_П){
      /* уточнення — лише питання; повний промпт сценарію тут робив би з нього бажання */
      const пер = await перекластиП('question', слова, null, 'review.followup');
      х.мова_шару.push(пер.запис);
      const q = (пер.внутрішня || {}).question; if (q && q.free_text) питання = q;
    }
    х.питання_внутрішня = питання;
    const к = р.картка_моделі || {};
    const попередня = {answer: к.відповідь, works: (к.вдало || []).map(п=>п.текст),
                       change: (к.змінити || []).map(п=>({id: п.ід, text: п.текст})),
                       earlier: р.допит.slice(0, -1).map(д=>({question: д.питання_внутрішня, answer: д.відповідь_моделі}))};
    /* промпт допиту — промпт оцінки того самого суду, її першого питання й мови + хвіст «now»; кадри ті самі */
    const п = await містП('оцінка', {крок: 'допит_промпт', суд: р.суд, питання, попередня, мова_тексту: р.мова,
                                     питання_оцінки: р.питання});
    if (!п || !п.промпт) throw new Error((п && п.помилка) || 'bridge_no_prompt: review.followup');
    let відп = await викликОцінкиП('допит', п.промпт, ОЦ.фото);
    let д = await містП('оцінка', {крок: 'допит', відповідь_моделі: відп});
    if (!д.відповідь){
      відп = await викликОцінкиП('допит · повтор формату', п.промпт + ПОВТОР_ФОРМАТУ_EN, ОЦ.фото);
      д = await містП('оцінка', {крок: 'допит', відповідь_моделі: відп});
    }
    if (!д.відповідь) throw new Error(д.причина || 'stylist_no_answer');
    х.відповідь_моделі = д.відповідь;
    let текст = д.відповідь;
    if (МОДЕЛЬ_МОВИ_П){
      const м = await мовоюП({відповідь: текст}, 'review.followup');
      х.мова_шару = х.мова_шару.concat(м.записи);
      текст = м.тексти['відповідь'] || текст;
    }
    х.відповідь = текст;
    if (стр) стр.appendChild(елЖінціП('div', 'репліка ші', текст, undefined, своїЕкрануП()));
    ст.textContent = '';
  }catch(e){
    х.помилка = String((e && e.message) || e);
    /* ПОКАЗ-1: код причини (`stylist_no_answer`…) жінці не йде (п.12) — він лишається в `х.помилка`
       і в записі виклику; на екрані стоїть сталий напис інтерфейсу. */
    ст.textContent = 'Не вдалося відповісти. Спробуй ще раз.';
  }finally{
    ОЦ.іде = false; if (кн) кн.disabled = false;
  }
}
