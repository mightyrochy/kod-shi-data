  const слова = String((поле && поле.value) || '').trim();
  if (!слова) return null;
  const спосіб = п.дом.голосом ? 'voice' : 'text';
  п.словаЙде = true; if (кн) кн.disabled = true; дотикП();
  ст.textContent = 'Переказую…';
  const початок = Date.now();
  let дії = [], запис = null;
  try{
    const пер = await перекластиП('review_items_fix', слова, {контекст: {items: п.для_слів}}, 'review.items_fix');
    запис = пер.запис; ОЦ.етапи.мова_шару.push(запис);
    дії = (пер.внутрішня || {}).actions || [];
  }catch(e){ запис = {причина: 'layer_failed: ' + String((e && e.message) || e)}; }
  const з = {слова, спосіб, від_перекладача: дії.length, мс_шару: Date.now() - початок, причина: (запис && запис.причина) || null,
             незнайомі: (запис && запис.незнайомі) || []};
  (п.звіт.слова = п.звіт.слова || []).push(з);
  let в = null;
