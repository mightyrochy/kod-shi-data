/* ── ПЕРЕЛІК «ЩО Я БАЧУ НА ФОТО» ───────────────────────────
   Після «Міряю кольори…» — рядок на річ: мініатюра за рамкою, місце
   сталим написом, кружечок кольору, назва мовним шаром, «замість» для запасної. «Так, оцінюй» активна одразу й не
   гейт (п.9): суд → ОЦІНКА → мова йдуть, не чекаючи її, а картка лише чекає дотику.
   Керування рукою: ✕ прибирає річ; рядок відкривається редактором: місце — чип, колір — кружечок,
   «в образі»/«замість»; «+ Річ» → місце → кружечок дописує річ без фото; дотик по фото в
   редакторі дописаної речі — код міряє вікно навколо нього, і промах (тло, шкіра) жінка виправляє кружечком, її вибір
   сильніший за вимір. Кожна дія йде кодами в `оцінка_образу.виправити_речі` (той самий вхід приймуть голос і текст)
   і обриває старий ланцюг оцінки: його результат відкидається, новий іде від суду. */
function дотикП(){ const п = ОЦ.перелік; if (п && !п.так) п.звіт.дотиків += 1; }
/* Її слова про перелік → хід `review_items_fix` на перекладачі → дії кодами → `виправитиПерелікП`. Поле
   очищається, лише коли хоч одна дія щось змінила: інакше слова лишаються, і вона виправляє їх рукою. */
async function виправитиСловамиП(слова, голосом){
  const п = ОЦ.перелік; if (!п || п.так || п.словаЙде) return null;
  слова = String(слова || '').trim();
  if (!слова) return null;
  const спосіб = голосом ? 'voice' : 'text';
  п.словаЙде = true; дотикП();
  показатиСтанФотоОцінки('слова', 'переказую');
  const початок = Date.now();
  let дії = [], запис = null, запасна = null;
  try{
    const пер = await перекластиП('review_items_fix', слова, {контекст: {items: п.для_слів}}, 'review.items_fix');
    запис = пер.запис; ОЦ.етапи.мова_шару.push(запис); запасна = пер.запасна;
    дії = (пер.внутрішня || {}).actions || [];
  }catch(e){ запис = {причина: 'layer_failed: ' + String((e && e.message) || e)}; запасна = 'items_fix_not_read'; }
  const з = {слова, спосіб, від_перекладача: дії.length, мс_шару: Date.now() - початок, причина: (запис && запис.причина) || null,
             незнайомі: (запис && запис.незнайомі) || []};
  (п.звіт.слова = п.звіт.слова || []).push(з);
  let в = null;
  if (дії.length && ОЦ.перелік === п && !п.так) в = await виправитиПерелікП(дії, спосіб);
  п.словаЙде = false;
  if (ОЦ.перелік !== п || п.так) return в;
  з.змінено = ((в || {}).дії || []).length;
  if (з.змінено) показатиСтанФотоОцінки('слова', 'виправила');
  else if (запасна) показатиЗбійФотоОцінки('слова', запасна, з.причина);   // запасний хід перекладача: сталий напис показу
  else показатиСтанФотоОцінки('слова', 'не_зрозуміла');
  return в;
}

/* ЇЇ ДОТИК ПО ФОТО: вікно навколо дотику — сама річ. Менша сторона фото ×
   ПІВВІКНА_ДОТИКУ_П — його півсторона; поля й ядра нема (`пікселіРечіП(…, безПоля)`); річ під дотиком і чи це тло — код (`виміряти_дотик`). */
const ПІВВІКНА_ДОТИКУ_П = 0.035;
const СТОРОНА_ФОТО_ДОТИКУ_П = 64;   // зменшене ціле фото до коду: тло кадру й чи дотик у ньому
async function пікселіДотикуП(ф, х, у){
  try{
    const бл = await (await fetch('data:' + (ф.тип || 'image/jpeg') + ';base64,' + ф.дані)).blob();
    const бм = await createImageBitmap(бл), W = бм.width, H = бм.height;
    if (бм.close) бм.close();
    const пів = ПІВВІКНА_ДОТИКУ_П * Math.min(W, H);
    const кл = v=>Math.max(0, Math.min(1000, Math.round(v)));
    const рамка = {ліво: кл((х * W - пів) / W * 1000), верх: кл((у * H - пів) / H * 1000),
                   право: кл((х * W + пів) / W * 1000), низ: кл((у * H + пів) / H * 1000)};
    const [пікселі, фото] = await Promise.all([пікселіРечіП(ф, рамка, true), пікселіРечіП(ф, null, true, СТОРОНА_ФОТО_ДОТИКУ_П)]);
    if (!пікселі) throw new Error('touch_pixels_unreadable');
    /* дотик: місце у вікні й на цілому фото (частками) + зменшене ціле фото — код відрізняє тло від речі */
    const вікноШ = Math.max(1, рамка.право - рамка.ліво), вікноВ = Math.max(1, рамка.низ - рамка.верх);
    пікселі.дотик = {x: (х * 1000 - рамка.ліво) / вікноШ, y: (у * 1000 - рамка.верх) / вікноВ};
    if (фото) пікселі.фото = Object.assign(фото, {x: х, y: у});
    return {рамка, пікселі};
  }catch(e){ показатиЗбійФотоОцінки('оцінка', 'touch_failed', e); return null; }
}
async function торкнутисяФотоП(р, ф, х, у){
  const п = ОЦ.перелік; if (!п || п.так) return;
  дотикП();
  const вікно = await пікселіДотикуП(ф, х, у);
  if (!вікно) return;
  const { ліво, верх, право, низ } = вікно.рамка;
  await виправитиПерелікП([{op: 'set', item: р.ід, photo: ф.ід, frame: {left: ліво, top: верх, right: право, bottom: низ}}],
                          'touch', {[р.ід]: вікно.пікселі});
}
/* Виправлення йдуть по одному: черга, бо кожне міняє перелік, з якого рахується наступне */
function виправитиПерелікП(дії, спосіб, пікселі){
  const п = ОЦ.перелік; if (!п || п.так) return Promise.resolve(null);
  const ч = (п.черга || Promise.resolve()).then(()=>застосуватиВиправленняП(п, дії, спосіб || 'touch', пікселі));
  п.черга = ч.catch(()=>null);
  return ч;
}
function зведенняСудуП(суд){
  const с = (суд && суд.суд) || {};
  return {рівень: суд.рівень || null, блокери: (с.blockers || []).map(б=>б.code || б.код || null),
          знахідки: (с.findings || []).map(з=>({правило: з.правило, речі: з.речі || []}))};
}
async function застосуватиВиправленняП(п, дії, спосіб, пікселіДотику){
  if (ОЦ.перелік !== п || п.так) return null;
  const в = await містП('оцінка', {крок: 'виправити', речі: п.речі, дії, лічильник: п.лічильник});
  if (ОЦ.перелік !== п || п.так) return null;
  if (!в || в.помилка){ (п.звіт.збої = п.звіт.збої || []).push(String((в && в.помилка) || 'bridge_no_answer')); return null; }
  if ((в.незнайомі || []).length) п.звіт.незнайомі = (п.звіт.незнайомі || []).concat(в.незнайомі);
  п.лічильник = Math.max(п.лічильник, в.лічильник || 0);          // ід `н…` не повторюється, навіть коли річ прибрано (рядок 5811)
  if (!(в.дії || []).length) return в;                            // нічого не змінилось: ланцюг не чіпаємо
  /* що суд казав до першого виправлення — лише коли він уже був готовий */
  if (!п.звіт.дії.length && ОЦ.етапи.суд && ОЦ.етапи.суд.суд) п.звіт.суд_до_виправлення = зведенняСудуП(ОЦ.етапи.суд);
  п.речі = в.речі; п.для_слів = в.для_слів || [];
  const мс = Date.now() - п.показано_о;
  в.дії.forEach(д=>п.звіт.дії.push(Object.assign({}, д, {спосіб, мс})));
  const змінені = new Set(в.дії.map(д=>д.ід)), є = new Set(п.речі.map(р=>р.ід));
  const ділянки = new Set(в.дії.filter(д=>д.поле === 'фото' || д.поле === 'рамка').map(д=>д.ід));
  for (const ід of змінені){
    const р = п.речі.find(х=>х.ід === ід);
    if (!р){ записатиПікселіРечіП(п.контекст, {ід}, null); continue; }
    if (!ділянки.has(ід)) continue;
    const ф = ОЦ.фото.find(х=>х.ід === р.фото);
    const кадр = (пікселіДотику || {})[ід] || (ф ? await пікселіРечіП(ф, р.рамка, true) : null);
    if (ОЦ.перелік !== п || п.так) return в;
    записатиПікселіРечіП(п.контекст, р, кадр);
  }
  Object.keys(п.hex).forEach(ід=>{ if (!є.has(ід)) delete п.hex[ід]; });
  const нова = спосіб === 'touch' ? в.дії.find(д=>д.op === 'add') : null;   // слова дописують без редактора: вона вже все сказала
  узгодитиРедакторРечей(нова && нова.ід, [...є]);
  /* кружечки й мініатюри змінених речей: центр вікна її слова, а в дотику без кольору — що поміряло вікно */
  const дотики = Object.fromEntries(Object.entries(п.контекст.пікселі).filter(([ід])=>є.has(ід) && ((п.речі.find(р=>р.ід === ід) || {}).дотик)));
  const кр = await містП('оцінка', Object.keys(дотики).length
    ? Object.assign({}, п.контекст.база, {крок: 'перелік', речі: п.речі, пікселі: дотики}) : {крок: 'перелік', речі: п.речі});
  for (const ід of змінені){
    const р = п.речі.find(х=>х.ід === ід);
    if (!р){ delete п.мініатюри[ід]; delete п.назви[ід]; continue; }
    п.hex[ід] = ((кр || {}).hex || {})[ід] || null;
    if (р.дотик && р.фото){
      const ф = ОЦ.фото.find(х=>х.ід === р.фото);
      п.мініатюри[ід] = (ф && (await кадрРечіУрлП(ф, р.рамка, 96))) || '';
    }
  }
  if (ОЦ.перелік !== п || п.так) return в;
  /* змінена річ без назви моделі фото: стара назва знімається, а з видом — нова з коду виду мовним шаром.
     Річ, чий вид змінено (`set` з `kind`), назву моделі фото теж втрачає: вона була про старий вид */
  const видЗмінено = new Set(в.дії.filter(д=>д.поле === 'вид').map(д=>д.ід));
  п.речі.forEach(р=>{ if (видЗмінено.has(р.ід)) р.назва = null; });
  const безНазви = new Set(п.речі.filter(р=>змінені.has(р.ід) && !р.назва).map(р=>р.ід));
  безНазви.forEach(ід=>{ delete п.назви[ід]; });
  if (безНазви.size) назвиПерелікуП(безНазви).catch(e=>ОЦ.етапи.мова_шару.push({напрям: 'out', де: 'review.items',
    причина: 'layer_failed: ' + String((e && e.message) || e)}));
  /* ОБРИВ: старий ланцюг падає на `signal` скасованої дії, його результат відкинуто, новий іде від суду */
  if (п.готовий) п.звіт.суд_перезапущено += 1;
  const біг = !!п.біжить;
  if (біг){ п.звіт.втрачено_мс += Date.now() - (п.ланцюг_о || Date.now()); скасуватиДіюП(п); }
  ОЦ.результат = null; ОЦ.етапи.суд = null; ОЦ.етапи.відповідь = null; ОЦ.етапи.картка = null;
  малюватиПерелікП();
  if (!біг && п.готовий) ланцюгПерелікуП();
  return в;
}
function підтвердитиПерелікП(подія){
  const п = ОЦ.перелік; if (!п || п.так) return;
  /* `відгук_мс` — скільки дотик чекав обробки (від події браузера до цього рядка): `мс_до_так` міряє ще й час, поки жінка
     читала перелік, а відгук сторінки — ця різниця */
  const в = подія && isFinite(подія.timeStamp) ? Math.round(performance.now() - подія.timeStamp) : null;
  п.так = true; п.звіт.дотиків += 1; п.звіт.мс_до_так = Date.now() - п.показано_о;
  if (п.доСуду) setTimeout(п.доСуду, 0);      // суд — після обробки дотику, не в ній
  п.звіт.відгук_мс = в !== null && в >= 0 && в < 600000 ? в : null;
  п.звіт.підсумок = п.речі.map(р=>({ід: р.ід, слот: р.слот, колір: р.колір, в_образі: р.в_образі, джерело: р.джерело || 'model',
                                  виправлено: р.виправлено || []}));
  малюватиПерелікП();
  малюватиКарткуОцінкиП();
}
/* Мініатюри й кружечки — до першого малювання; назви мовного шару — паралельно з судом (п.12: слова пише шар,
   не код), вони лише доповнюють готові рядки. Нема мовної моделі — назви нема, рядок тримається місцем і кольором. */
async function показатиПерелікП(речі){
  const в = (await містП('оцінка', {крок: 'перелік', речі})) || {};
  const мініатюри = {};
  for (const р of речі){
    const ф = ОЦ.фото.find(х=>х.ід === р.фото);
    мініатюри[р.ід] = (ф && (await кадрРечіУрлП(ф, р.рамка, 96))) || (ф ? урлФотоП(ф) : '');
  }
  const звіт = {показано: речі.length, дії: [], дотиків: 0, мс_до_так: null, відгук_мс: null, суд_перезапущено: 0,
                суд_до_виправлення: null, втрачено_мс: 0};
  ОЦ.перелік = {речі: речі.map(р=>Object.assign({}, р)), hex: в.hex || {}, довідник: в.довідник || {слоти: [], кольори: []},
                мініатюри, назви: {}, так: false, показано_о: Date.now(), звіт, ід_ланцюга: ОЦ.ід,
                біжить: false, готовий: false,
                лічильник: 0, для_слів: в.для_слів || [], словаЙде: false};
  ОЦ.етапи.підтвердження = звіт;
  скинутиРедакторРечей();
  малюватиПерелікП();
  /* перший показ: перелік — на екран цілим; кнопка лишається над панеллю й тоді, коли речей багато */
  прокрутитиРечіОцінки();
}
/* Річ без назви моделі фото, але з видом (дописана словами чи дотиком — `add` з `kind`), іде в шар кодом виду: назву з
   нього пише мовна модель (п.12: код слів не пише). `ідс` — лише ці речі (після виправлення), без нього —
   увесь перелік. Річ, чия назва чи вид змінились, поки шар працював, назви з цього виклику не бере. */
async function назвиПерелікуП(ідс){
  const п = ОЦ.перелік; if (!п || !МОДЕЛЬ_МОВИ_П) return;
  const т = {};
  п.речі.forEach(р=>{ if ((!ідс || ідс.has(р.ід)) && (р.назва || р.вид)) т['річ.' + р.ід] = р.назва || р.вид; });
  if (!Object.keys(т).length) return;
  const м = await мовоюП(т, 'review.items');
  м.записи.forEach(з=>ОЦ.етапи.мова_шару.push(з));
  if (ОЦ.перелік !== п) return;
  п.речі.forEach(р=>{
    const к = 'річ.' + р.ід;
    if (к in т && т[к] === (р.назва || р.вид) && !чужоюМовоюП(м.тексти[к], своїВходуП(т[к]))) п.назви[р.ід] = String(м.тексти[к] || '');
  });
  малюватиПерелікП();
}
/* Кружечок після суду: вимір кадру (hex), де він певний, замість центру вікна слова */
function записатиПікселіРечіП(контекст, річ, кадр){
  /* Обидва читачі ділянки отримують той самий кадр; старі фото після переносу чи дотику знімаються. */
  if (кадр){
    контекст.пікселі[річ.ід] = кадр;
    контекст.пікселі_фото[річ.ід] = {[річ.фото]: кадр};
  } else {
    delete контекст.пікселі[річ.ід]; delete контекст.пікселі_фото[річ.ід];
  }
}
async function виміриВПерелікуП(суд){
  const п = ОЦ.перелік; if (!п) return;
  const дія = чиннаДіяП(п);
  for (const р of (суд.речі || [])){
    const ід = р.ід, hex = (р.вимір || {}).lab ? (р.вимір || {}).hex : null;
    const запис = п.речі.find(х=>х.ід === ід);
    if (запис && запис.фото !== р.фото){
      const кадр = ((п.контекст.пікселі_фото || {})[ід] || {})[р.фото];
      Object.assign(запис, {фото: р.фото, рамка: р.рамка});
      записатиПікселіРечіП(п.контекст, запис, кадр);
      const ф = ОЦ.фото.find(х=>х.ід === р.фото);
      const мініатюра = ф ? await кадрРечіУрлП(ф, р.рамка, 96) : '';
      if (ОЦ.перелік !== п || (дія && !дія.чинна()) || п.речі.find(х=>х.ід === ід) !== запис) return;
      п.мініатюри[ід] = мініатюра;
    }
    if (hex && п.речі.some(х=>х.ід === ід)) п.hex[ід] = hex;
  }
  малюватиПерелікП();
}
/* Рядок сцени над карткою — тими самими словами, що в картці сценарію (довідник) */
function рядокСценаріюОцінкиП(с){
  const ч = [];
  const н = знайти(ДОВІДНИК.нагоди, (с || {}).нагода); if (н) ч.push(н.підпис);
  if (с && ВІДЧУТТЯ_П[с.смуга_погоди]) ч.push(ВІДЧУТТЯ_П[с.смуга_погоди]);
  const оп = ОПАДИ.find(([к])=>к === (с || {}).опади); if (оп) ч.push(оп[1].toLowerCase());
  return ч.join(' · ');
}

/* ЗАПИС У ФАЙЛ ВЕРДИКТІВ — З УСІМА ЕТАПАМИ (власник: «абсолютно всі проблеми й етапи рішення»).
   Та сама сховищна таблиця й ті самі шапкові поля, що в рук (`записати`), тож файл і TSV
   беруть оцінку без окремого читача; `рука: 'оцінка'` і свій `розклад` роблять її окремим
   прогоном. Ребер калібрування тут нема свідомо: калібрування міряє правила на образах, які
   СКЛАЛА система, і її власний образ змішав би дві різні вибірки. */
async function записатиОцінкуП(){
  const поз = 'оц', в = відповідь(поз), р = ОЦ.результат;
  if (!р) return;
  if (!єЩоЗаписатиП(в)){ показатиСтанФотоОцінки('вердикт', 'нема_що_записати'); return; }
  const с = р.суд || {}, образ = new Set(с.образ || []);
  const згода = згодаПрофіляП();
  const вх = згода ? вхідОцінкиП() : безКольорівБезЗгодиП(вхідОцінкиП());
  const запис = {
    дата: new Date().toISOString().slice(0, 10), профіль: вх.імʼя || ПІДПИС_БЕЗІМЕННОЇ_П, рука: 'оцінка', пул: '—',
    модель: р.модель || МОДЕЛЬ_П || '?', склад: (с.образ || []).join('+') || '—', підпис: '',
    текст: р.відповідь_сира || '', опис: (р.картка || {}).відповідь || '', як_носити: [],
    мова_шару: ((р.картка || {}).мова_шару || []),
    вердикт_людини: (в.верд || ''), для_мене: (в.для_мене || ''), після_примірки: false,
    паспорт: JSON.stringify(null), паспорт_джерело: '—', чат_повідомлень: 0, чат: JSON.stringify([]),
    ...поляВердиктуП(в), замінити: '', позиція: 1, розклад: 'оцінка·' + ОЦ.ід,
    /* Її власний образ — теж окремий прогін, і ід у нього свій (наряд Л-7): `ОЦ.ід`
       вже унікальний на кожне «Оціни мій образ», тож новий не вигадується. */
    прогін: 'оц-' + ОЦ.ід,
    знахідки_коду: ((с.суд || {}).findings || []).slice(), питання_коду: [],
    збірка: ЗБІРКА_ПОКАЗУ, каталог: КАТАЛОГ_ПІДПИС_П,
    драп_білий: згода ? ДРАП.білий : null, драп_метал: згода ? ДРАП.метал : null,
    драп_нейтралі: згода ? ДРАП.нейтралі : null, самозвіт_барви: згода ? ДРАП.барви : null,
    джерело: 'показ-v3', пристрій, час: new Date().toISOString(),
    коментар: (в.коментар || '').trim(), коментар_голосом: !!в.коментар_голосом && !!(в.коментар || '').trim(),
    /* що вона питала й що прочитала на картці — поруч із сирою відповіддю моделі (`текст`) */
    оцінка_питання: ОЦ.етапи.питання || '', оцінка_картка: р.картка,
    речі_образу: (с.речі || []).filter(x=>образ.has(x.ід)).map(x=>({id: x.ід, назва: x.назва, слот: x.слот, тип: x.вид,
      колір: ((x.вимір || {}).слово || x.колір), hex: (x.вимір || {}).hex, фото: x.фото})),
    етапи: JSON.stringify(Object.assign({}, ОЦ.етапи, {допит: р.допит})),
    вхід_прогону: Object.assign(вх, {сценарій_оцінки: р.сценарій})
  };
  let запасна = null;
  if (МОДЕЛЬ_МОВИ_П && запис.коментар){
    показатиСтанФотоОцінки('вердикт', 'читає');
    const пер = await перекластиП('verdict_comment', запис.коментар,
      {речі: запис.речі_образу,
       контекст: дотикДляПерекладуП(в)}, 'verdict.review');
    запис.коментар_внутрішня = пер.внутрішня; запис.мова_шару_коментаря = [пер.запис];
    if (пер.запасна) запис.коментар_внутрішня_чому = пер.запис.причина + ' · raw_comment=kept';
    запасна = пер.запасна;
    показатиСтанФотоОцінки('вердикт', 'порожньо');
  }
  запис.зведено = зведенийВердиктП(в, запис.коментар_внутрішня);
  try{
    const d = await дб();
    await tx(d, 'вердикти', 'readwrite', s=>s.add(запис));
    в.записано = true; показатиСтанФотоОцінки('вердикт', 'записано');
    if (запасна) показатиЗбійФотоОцінки('вердикт', запасна, запис.коментар_внутрішня_чому);   // коментар не прочитано — вона це бачить
    коментарЗаписаноП(поз, запис.коментар);
    оновитиЖурнал();
  }catch(e){ показатиЗбійФотоОцінки('вердикт', 'not_written', e); }
}
/* ЗБІЙ ОЦІНКИ — ТЕЖ У ФАЙЛ (той самий принцип, що власник назвав для рук, які впали:
   «має потрапляти у файл з усіма етапами й причиною»). Картки нема, вердикта жінка не
   ставила — запис несе крок, на якому стало (`оцінка_помилка`), і всі етапи до нього. */
async function записатиЗбійОцінкиП(){
  try{
    const згода = згодаПрофіляП();
    const вх = згода ? вхідОцінкиП() : безКольорівБезЗгодиП(вхідОцінкиП());
    const запис = {дата: new Date().toISOString().slice(0, 10), профіль: вх.імʼя || ПІДПИС_БЕЗІМЕННОЇ_П, рука: 'оцінка',
      пул: '—', модель: МОДЕЛЬ_П || '?', склад: '—', підпис: '', текст: '', опис: '', вердикт_людини: '',
      позиція: 1, розклад: 'оцінка·' + ОЦ.ід, прогін: 'оц-' + ОЦ.ід,
      збірка: ЗБІРКА_ПОКАЗУ, каталог: КАТАЛОГ_ПІДПИС_П,
      джерело: 'показ-v3', пристрій, час: new Date().toISOString(),
      оцінка_питання: (ОЦ.етапи || {}).питання || '', оцінка_помилка: (ОЦ.етапи || {}).помилка || '',
      етапи: JSON.stringify(ОЦ.етапи || {}),
      вхід_прогону: Object.assign(вх, {сценарій_оцінки: (ОЦ.етапи || {}).сценарій_екрана || {}})};
    const d = await дб();
    await tx(d, 'вердикти', 'readwrite', s=>s.add(запис));
    оновитиЖурнал();
  }catch(e){ показатиЗбійФотоОцінки('загальне', 'not_written', e); }
}
/* ДОПИТ ПІД КАРТКОЮ: її нове питання — перекладачеві, далі модель із тими самими фото й
   тим самим судом, плюс те, що вона вже сказала; відповідь — мовною моделлю. */

async function допитОцінкиП(слова){
  const р = ОЦ.результат;
  слова = String(слова || '').trim();
  if (!слова || !р || ОЦ.іде) return;
  ОЦ.іде = true;
  const х = {питання: слова, коли: new Date().toISOString(), мова_шару: []};
  р.допит.push(х);
  показатиДопитОцінки(true);
  try{
    показатиСтанФотоОцінки('допит', 'думаю');
    let питання = {free_text: слова, lang: 'uk'};
    if (МОДЕЛЬ_МОВИ_П){
      /* уточнення — лише питання; повний промпт сценарію тут робив би з нього бажання */
      const пер = await перекластиП('question', слова, null, 'review.followup');
      х.мова_шару.push(пер.запис);
      const q = (пер.внутрішня || {}).question; if (q && q.free_text) питання = q;
    }
    х.питання_внутрішня = питання;
    const к = р.картка_моделі || {};
    const попередня = {answer: к.відповідь, works: (к.вдало || []).map(п=>п.текст),
                       change: (к.змінити || []).map(п=>({id: п.ід, text: п.текст})),
                       earlier: р.допит.slice(0, -1).map(д=>({question: д.питання_внутрішня, answer: д.відповідь_моделі}))};
    /* промпт допиту — промпт оцінки того самого суду, її першого питання й мови + хвіст «now»; кадри ті самі */
    const п = await містП('оцінка', {крок: 'допит_промпт', суд: р.суд, питання, попередня, мова_тексту: р.мова,
                                     питання_оцінки: р.питання});
    if (!п || !п.промпт) throw new Error((п && п.помилка) || 'bridge_no_prompt: review.followup');
    let відп = await викликОцінкиП('допит', п.промпт, ОЦ.фото);
    let д = await містП('оцінка', {крок: 'допит', відповідь_моделі: відп});
    if (!д.відповідь){
      відп = await викликОцінкиП('допит · повтор формату', п.промпт + ПОВТОР_ФОРМАТУ_EN, ОЦ.фото);
      д = await містП('оцінка', {крок: 'допит', відповідь_моделі: відп});
    }
    if (!д.відповідь) throw new Error(д.причина || ПРИЧИНА_БЕЗ_ВІДПОВІДІ_П);
    х.відповідь_моделі = д.відповідь;
    let текст = д.відповідь;
    if (МОДЕЛЬ_МОВИ_П){
      const м = await мовоюП({відповідь: текст}, 'review.followup');
      х.мова_шару = х.мова_шару.concat(м.записи);
      текст = м.тексти['відповідь'] || текст;
    }
    х.відповідь = текст;
    показатиДопитОцінки();
    показатиСтанФотоОцінки('допит', 'порожньо');
  }catch(e){
    х.помилка = String((e && e.message) || e);
    /* ПОКАЗ-1: код причини (`stylist_no_answer`…) жінці не йде (п.12) — він лишається в `х.помилка`
       і в записі виклику; на екрані стоїть сталий напис інтерфейсу. */
    показатиСтанФотоОцінки('допит', 'збій_відповіді');
  }finally{
    ОЦ.іде = false; показатиДопитОцінки();
  }
}

