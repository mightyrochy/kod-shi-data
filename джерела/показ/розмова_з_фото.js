/* ЇЇ ДОТИК ПО ФОТО: вікно навколо дотику — сама річ. Менша сторона фото ×
   ПІВВІКНА_ДОТИКУ_П — його півсторона; поля й ядра нема (`пікселіРечіП(…, безПоля)`); річ під дотиком і чи це тло — код (`виміряти_дотик`). */
const ПІВВІКНА_ДОТИКУ_П = 0.035;
const СТОРОНА_ФОТО_ДОТИКУ_П = 64;   // зменшене ціле фото до коду: тло кадру й чи дотик у ньому
async function пікселіДотикуП(ф, х, у){
  try{
    const бл = await (await fetch('data:' + (ф.тип || 'image/jpeg') + ';base64,' + ф.дані)).blob();
    const бм = await createImageBitmap(бл), W = бм.width, H = бм.height;
    if (бм.close) бм.close();
    const пів = ПІВВІКНА_ДОТИКУ_П * Math.min(W, H);
    const кл = v=>Math.max(0, Math.min(1000, Math.round(v)));
    const рамка = {ліво: кл((х * W - пів) / W * 1000), верх: кл((у * H - пів) / H * 1000),
                   право: кл((х * W + пів) / W * 1000), низ: кл((у * H + пів) / H * 1000)};
    const [пікселі, фото] = await Promise.all([пікселіРечіП(ф, рамка, true), пікселіРечіП(ф, null, true, СТОРОНА_ФОТО_ДОТИКУ_П)]);
    if (!пікселі) return null;
    /* дотик: місце у вікні й на цілому фото (частками) + зменшене ціле фото — код відрізняє тло від речі */
    const вікноШ = Math.max(1, рамка.право - рамка.ліво), вікноВ = Math.max(1, рамка.низ - рамка.верх);
    пікселі.дотик = {x: (х * 1000 - рамка.ліво) / вікноШ, y: (у * 1000 - рамка.верх) / вікноВ};
    if (фото) пікселі.фото = Object.assign(фото, {x: х, y: у});
    return {рамка, пікселі};
  }catch(e){ return null; }
}
