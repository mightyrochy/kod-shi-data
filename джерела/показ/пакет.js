async function позначитиВивантаженіП(ключі, коли){
  if (!(ключі||[]).length) return;
  const d = await дб();
  const іс = коли.toISOString();
  return tx(d, 'вердикти', 'readwrite', s=>{
    ключі.forEach(к=>{
      const r = s.get(к);
      r.onsuccess = ()=>{
        const з = r.result; if (!з) return;
        з.вивантажено = [...(з.вивантажено || []), іс];
        s.put(з, к);
      };
    });
  });
}

/* Прибирає машинні сліди з тексту, який читає людина, і виймає оголошені
   ходи ші («СВІДОМО: …» / «як_носити») окремо. Повертає [опис, [задуми]].
   Одна функція на рендер і приміряння — дві копії розійшлися б.

   ОПИС ЇДЕ ПОЛЕМ, А НЕ РЯДКОМ (Т-04). Проза для жінки живе в ОДНОМУ місці
   протоколу — полі `текст` обʼєкта ОПИС_ВІДПОВІДЬ_V1 (§1(в)); `як_носити` —
   це «Як це носити» на картці, той самий блок, що доти збирався з рядків
   «СВІДОМО:». Решта обʼєктів моделі (склад, ремонт, вибір) — не текст для
   людини: картка без опису чесніша за сирий об'єкт (05.09).
   ПОВЕРТАЄМО ЗАВЖДИ МАСИВ. Тут стояло `return {текст:'', задум:[]}` — обʼєкт
   там, де обидва викликачі роблять `const [опис, задум] = людською(...)`. Тобто
   на будь-якому JSON у полі `текст` картки рендер падав TypeError (об'єкт не
   ітерується) — і замість картки жінка діставала порожній екран. */
function людською(сирий, готове, лишитиHex){
  const задум = [];
  let текстП = String(сирий||'');
  /* ── ГОТОВЕ ПОЛЕ СИЛЬНІШЕ ЗА ДРУГИЙ РОЗБІР ──────────────
     Прозу для жінки з відповіді моделі вже вийняв Python
     (`pipeline.опис_відповідь_з_json`) — толерантно до прози довкола JSON і до
     хвоста після нього. Тут стояв ДРУГИЙ розбирач над тим самим сирим текстом:
     `JSON.parse` після зняття ``` — і він мовчки розходився з першим на кожній
     відповіді, яка не була чистим JSON. «Проза + JSON» → на картку їхав сирий
     префікс прози разом із фігурними дужками; «JSON + хвіст» → parse падав, а
     далі гілка «схоже на обʼєкт» повертала ПОРОЖНЮ картку. Тепер картка подає
     сюди готові поля, а розбір сирого тексту лишається тим, чим і був, — шляхом
     для рук без каталогу (3 і 4), де обʼєкта опису нема за побудовою.
     ЧИСТКА СПІЛЬНА: машинні сліди (hex, id, коди правил, markdown) знімаються
     нижче з обох шляхів однаково — це останній ярус перед очима жінки. */
  if (готове && typeof готове === 'object' && String(готове.текст || '').trim()){
    текстП = String(готове.текст);
    for (const р of (Array.isArray(готове.як_носити) ? готове.як_носити : []))
      if (String(р||'').trim()) задум.push(String(р).trim());
  } else if (/^\s*[\{\[]/.test(текстП.trim()) || /```/.test(текстП)){
    let об = null;
    const безОгорож = текстП.replace(/```(?:json)?/g,'').trim();
    try{ об = JSON.parse(безОгорож); }catch(_){}
    if (об && typeof об === 'object' && typeof об.текст === 'string'){
      текстП = об.текст;
      for (const р of (Array.isArray(об.як_носити) ? об.як_носити : []))
        if (String(р||'').trim()) задум.push(String(р).trim());
    } else if (/^[\{\[]/.test(безОгорож) || /"образи"\s*:|"речі"\s*:\s*\[/.test(текстП)){
      /* JSON У ОГОРОЖІ ```json, ЯКИЙ НЕ РОЗІБРАВСЯ (s13, 25.09: «\» + перенос у рядку) —
         теж не текст для людини: доти огорожа ховала «{» від перевірки вище, і на
         картку «Чому цей образ» ішов сирий обʼєкт із \n і \. */
      return ['', []];
    }
  }
  const рядки = текстП.split('\n').filter(л=>{
    const t = л.trim();
    if (/^(ОБРАЗ|ПІДПИС|ФОТО НЕ ТЕ)\s*[:：]/i.test(t)) return false;
    const c = t.match(/^(?:СВІДОМО|Свідомо|свідомо|НАВМИСНО|Навмисно)\s*[:—–-]\s*(.+)$/);
    if (c){ задум.push(c[1].trim()); return false; }
    return true;
});
  /* ЧИСТКА ОДНА НА ОБИДВА ВИХОДИ (Т-06). Доти вона стояла лише над прозою, а
     рядки «Як це носити» («СВІДОМО:», тепер поле `як_носити`) ішли на картку
     СИРИМИ — і номер речі чи hex у пораді доїжджав до жінки, хоч у сусідньому
     абзаці його вирізали. ID правил тут додано з тієї ж причини: до моделі вони не
     їдуть (`bridge._вердикт_для_моделі`), але картка — останній ярус, і «K-COL-02»
     у тексті для жінки є збоєм, а не поясненням. */
  /* `лишитиHex` — лише для входу мовного шару: hex там стає кодом кольору
     (`мовний_шар.кольори_кодом`), і шар пише його назву. Показ жінці — без hex, як доти. */
  const чистий = т => безМашинногоСліду(т, лишитиHex);
  return [чистий(рядки.join('\n')), задум.map(чистий).filter(Boolean)];
}
/* ── ОСТАННІЙ ЯРУС ПЕРЕД ОЧИМА ЖІНКИ — ОДИН НА ВЕСЬ ПОКАЗ ──────────────────
   Ця чистка жила локальною стрілкою всередині `людською()` і працювала лише над
   прозою образу. На картку приходить ДРУГИЙ текст коду — перелік «код
   не знає» (`в.питання`), і стенд показав чому це важливо: рядок
   `fit.py` «довжина речі невідома — край рахується на дефолті слота; K-FIT-03
   утримано» виносив код правила просто на картку, на всіх чотирьох руках.
   Тому чистка стала спільною функцією: ОДИН свідок того, що жінці не показують
   машинних слідів (hex, id, номери, markdown, ID правил), скільки б текстів на
   картку не приходило. Чистимо ПОКАЗ, не дані: у звіт (`питання_коду`) і в
   журнал їде той самий рядок коду, як його написав `суд_*`.
   `лишитиHex`: текст іде НЕ жінці, а в мовний шар, і hex там — колір речі, який
   Python кладе кодом (`мовний_шар.кольори_кодом`). Значення ховається від чистки знаками
   приватної зони Unicode і вертається після неї; ярлик «hex» знімається, як і доти. */
const _HEX_СХОВ_П = /#([0-9a-fA-F]{6})\b/g, _HEX_ВЕРНУТИ_П = /\uE000([0-9a-fA-F]{6})\uE001/g;
const безМашинногоСліду = (s, лишитиHex) => (лишитиHex
    ? _безМашинногоСліду(String(s||'').replace(_HEX_СХОВ_П, '\uE000$1\uE001')).replace(_HEX_ВЕРНУТИ_П, '#$1')
    : _безМашинногоСліду(s));
const _безМашинногоСліду = (s) => String(s||'')
    .replace(/\*\*([^*\n]+)\*\*/g, '$1').replace(/(^|\n)[ \t]*[*•]\s+/g, '$1')
    .replace(/[A-Za-zА-Яа-яІіЇїЄєҐґ]{1,3}-\d{2,}@[\w\-]+(?:\.[\w\-]+)*/g, '')
    .replace(/#\d+\s*[·.\-]\s*\d{2}/g, '')
    .replace(/#[0-9a-fA-F]{6}\b/g, '')
    .replace(/\b[KRКР]-[A-ZА-Я]{2,6}-\d{2}[a-zа-я]?\b/g, '')
    // ЯРЛИК МАШИНИ ЗНІМАЄТЬСЯ РАЗОМ ІЗ ЗНАЧЕННЯМ (З-5б).
    // Якщо знімати лише ЗНАЧЕННЯ `#2C2F33` і порожні дужки, дужка з
    // ярликом порожньою не була: модель пише «колір графіт (hex #2C2F33)», картка
    // руки 4 читалась «колір графіт (hex )» — шість разів на одному аркуші. Звірка
    // стенда «на жодній картці нема hex» цього не ловила: вона шукала значення.
    // Тому ярлик іде разом зі значенням, і значення тут необов'язкове — так само
    // знімається ярлик, що лишився сам (порядок правил у чистці не має значення).
    // Ярлики простору кольору, а не лише hex: одне слово машини для жінки — збій.
    // `lab` у переліку НЕМА свідомо: це єдиний ярлик, що є ще й звичайним словом
    // (у каталозі «COGWE-F09181 LAB-BLEU»), а в прозі моделі він не трапляється —
    // hex трапився. Решта (rgb, hsl, lch, cmyk) словами не бувають.
    // Дві форми, і функційна ЙДЕ ПЕРШОЮ, інакше від «rgb(94,107,75)» лишились би
    // самі числа в дужках — машинний слід, лише без імені.
    .replace(/\b(?:rgba?|hsla?|lch|cmyk)\s*\([^)\n]*\)/gi, '')
    .replace(/\b(?:hex|rgba?|hsla?|lch|cmyk)\b\s*(?:-?\s*код\w*)?\s*[:=]?\s*(?:#?[0-9a-fA-F]{6}\b)?/gi, '')
    // id вигаданих речей рук 3–4 (`розбір_відповідей.py`: offer id="м-%03d") — той
    // самий машинний слід, що й id каталогу вище, лише свій шаблон («м-001»
    // доходило до картки, бо під жоден із патернів
    // вище не підпадало). \b тут не годиться — Cyrillic-літера для JS не \w, тож
    // межу слова перевіряємо вручну по сусідніх символах.
    .replace(/(?<![A-Za-zА-Яа-яІіЇїЄєҐґ0-9])м-\d{3,}(?![A-Za-zА-Яа-яІіЇїЄєҐґ0-9])/g, '')
    .replace(/[ \t]*[—–-]\s*(?=\n|$)/g, '')
    // порожня дужка знімається ДО згортання пробілів: вирізане «(K-COL-02)» лишало
    // по собі два пробіли, і картка читалась «у тоні  — лишаємо»
    // ...і дужка, у якій від вирізаного лишилась лише пунктуація: «(hex , rgb )»
    // згортається до «( , )», а це той самий машинний слід очима (З-5б).
    .replace(/\(\s*[,;:·.–—-]*\s*\)/g, '')
    // те саме для порожніх «»: вирізаний id вигаданої речі лишає по собі
    // guillemets навколо нічого — «» на «груди»: нижче мінімуму носіння…
    .replace(/«\s*»/g, '')
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/\n{3,}/g, '\n\n')
    .replace(/\s+([,.;:!?])/g, '$1')
    .replace(/([,;:])\s*(?=[,.;:])/g, '')
    .replace(/(^|\n)\s*[,.;:]\s*/g, '$1')
    .trim();

