/* ── IndexedDB: вердикти + пристрій-id ──────────────────────────────────── */
let зʼєднанняДбП = null, відкриттяДбП = null;
/* Повторно використовує зʼєднання й обʼєднує одночасні запити відкриття.
   Зміна версії закриває його для іншої вкладки; наступний виклик відкриє заново. */
function дб(){
  if (зʼєднанняДбП) return Promise.resolve(зʼєднанняДбП);
  if (відкриттяДбП) return відкриттяДбП;
  const відкриття = new Promise((рез, від)=>{
    const з = indexedDB.open('показ', 3);
    з.onupgradeneeded = е=>{
      const d = е.target.result;
      if (!d.objectStoreNames.contains('вердикти')) d.createObjectStore('вердикти',{autoIncrement:true});
      if (!d.objectStoreNames.contains('кв')) d.createObjectStore('кв');
      /* v2: образи лишаються на телефоні — бібліотека за випадками,
         повторне судження. Ключ — збірка·розклад·профіль; вердикти в'яжуться
         до нього тими ж полями + позиція. */
      if (!d.objectStoreNames.contains('образи')) d.createObjectStore('образи');
      /* v3 (інтерфейс v4): бібліотека сценаріїв — збережені випадки
         разом із паспортом, розмовою й вибором палітри; ключ — ід сценарію. */
      if (!d.objectStoreNames.contains('сценарії')) d.createObjectStore('сценарії');
    };
    з.onblocked = ()=>console.warn('Відкриття сховища чекає закриття іншої вкладки');
    з.onsuccess = ()=>{
      const d = з.result;
      const забути = ()=>{ if (зʼєднанняДбП === d) зʼєднанняДбП = null; };
      const закрити = d.close.bind(d);
      d.close = ()=>{ забути(); закрити(); };
      d.onversionchange = ()=>d.close();
      d.onclose = забути;
      зʼєднанняДбП = d;
      рез(d);
    };
    з.onerror = ()=>від(з.error);
  });
  відкриттяДбП = відкриття;
  відкриття.then(
    ()=>{ if (відкриттяДбП === відкриття) відкриттяДбП = null; },
    ()=>{ if (відкриттяДбП === відкриття) відкриттяДбП = null; }
  );
  return відкриття;
}
function tx(d, ім, режим, дія){
  return new Promise((рез, від)=>{
    const журнал = ім === 'вердикти' && режим === 'readwrite';
    if (журнал) скинутиКешЖурналуП();
    const t = d.transaction(журнал ? ['вердикти', 'кв'] : ім, режим), s = t.objectStore(ім);
    if (журнал){
      const кв = t.objectStore('кв'), версія = кв.get(КЛЮЧ_РЕВІЗІЇ_ЖУРНАЛУ_П);
      версія.onsuccess = ()=>кв.put((версія.result || 0) + 1, КЛЮЧ_РЕВІЗІЇ_ЖУРНАЛУ_П);
    }
    const r = дія(s);
    t.oncomplete = ()=>{ if (журнал) скинутиКешЖурналуП(); рез(r && r.result); };
    t.onerror = ()=>від(t.error);
    if (журнал) t.onabort = ()=>{ скинутиКешЖурналуП(); від(t.error || new Error('journal_write_aborted')); };
  });
}
