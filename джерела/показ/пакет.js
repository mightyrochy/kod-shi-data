const КЛЮЧ_РЕВІЗІЇ_ЖУРНАЛУ_П = 'версія_вердиктів';
const МЕЖА_ЖУРНАЛУ_П = {символів: 8 * 1024 * 1024};
let КЕШ_ЖУРНАЛУ_П = null, ЧИТАННЯ_ЖУРНАЛУ_П = null, ПОКОЛІННЯ_ЖУРНАЛУ_П = 0;
function скинутиКешЖурналуП(){
  КЕШ_ЖУРНАЛУ_П = null; ЧИТАННЯ_ЖУРНАЛУ_П = null; ПОКОЛІННЯ_ЖУРНАЛУ_П++;
}
async function знімокЖурналуП(){
  const покоління = ПОКОЛІННЯ_ЖУРНАЛУ_П;
  const d = await дб();
  d.addEventListener('versionchange', скинутиКешЖурналуП);
  d.addEventListener('close', скинутиКешЖурналуП);
  return new Promise((рез, від)=>{
    const t = d.transaction(['кв', 'вердикти'], 'readonly');
    const r = t.objectStore('кв').get(КЛЮЧ_РЕВІЗІЇ_ЖУРНАЛУ_П);
    let ревізія, рядки, ключі, записи;
    r.onsuccess = ()=>{
      ревізія = r.result || 0;
      if (КЕШ_ЖУРНАЛУ_П && КЕШ_ЖУРНАЛУ_П.ревізія === ревізія){
        рядки = КЕШ_ЖУРНАЛУ_П.рядки; return;
      }
      const s = t.objectStore('вердикти');
      const к = s.getAllKeys(), з = s.getAll();
      к.onsuccess = ()=>{ ключі = к.result; };
      з.onsuccess = ()=>{ записи = з.result; };
    };
    t.oncomplete = ()=>{
      if (!рядки) рядки = (записи || []).map((зап, і)=>({ключ: ключі[і], зап}));
      if (покоління === ПОКОЛІННЯ_ЖУРНАЛУ_П) КЕШ_ЖУРНАЛУ_П = {ревізія, рядки};
      рез(рядки);
    };
    t.onerror = ()=>від(t.error);
    t.onabort = ()=>від(t.error || new Error('journal_read_aborted'));
  });
}
