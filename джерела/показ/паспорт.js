/* ── РІЧ З ФОТО: ВИМІР КОЛЬОРУ Й ВЕРДИКТ КОДУ ──────────────────────
   Модель у виклику 0 назвала річ і РАМКУ на фото; колір міряє КОД — пікселями в межах
   рамки, без тла й шкіри (`річ_з_фото.виміряти`). Рамку вирізає й кадр зменшує телефон:
   у Python їде лише ≤128×128 пікселів RGB, а фото лишається тут. Вердикт «чи підійде»
   (`річ_з_фото.вердикт`) стоїть у репліці стилістки реченням коду й лягає в паспорт, звідки
   модель його переказує на наступних ходах і не суперечить йому. */
const МАКС_СТОРОНА_ВИМІРУ_П = 128;   // = річ_з_фото.МАКС_СТОРОНА
/* ПОЛЕ НАВКОЛО РАМКИ МОДЕЛІ. Промпт веде модель малювати рамку «tight around the item
   itself, without background», а код бере тло з країв кадру (`річ_з_фото.маска`: медіана смуги по краях). Із
   щільною рамкою ці краї — сама річ: тло виходило б кольором речі, і міряло б те, що від нього відрізняється —
   жакет хакі з блакитною сорочкою всередині вимірявся б як «білий» (#d0d8e3), а річ усередині плями речі
   «не відділялась від тла» (0.0 %). Тож показ вирізає рамку з полем (12 % її сторін, не за межі фото) і
   каже, де в кадрі сама рамка: `ядро` в тисячних кадру — код обирає пляму речі за ядром. */
const ПОЛЕ_РАМКИ_П = 0.12;
/* РОЗКОДОВАНИЙ КАДР ФОТО — ОДИН НА ФОТО, А НЕ НА КОЖНУ РІЧ. Оцінка знає свої фото ще до відповіді моделі,
   тож `прогрітиКадриП` розкодовує їх, поки модель дивиться; після її відповіді виміри речей і мініатюри переліку беруть
   готовий кадр (`кадрФотоП`) і мають лише синхронну роботу з canvas. Розкодування на кожну річ окремо
   (`fetch` → `blob` → `createImageBitmap`, три очікування на річ) було б довшим: головний потік у ті секунди ділиться з кроком
   «каталог» у Pyodide, кожне очікування чекало б свого ходу, і перелік з'являвся б не раніше кінця каталогу.
   Кеш живе рівно доти, доки оцінка будує перелік (`звільнитиКадриП`);
   пізніші виправлення переліку розкодовують самі. */
let КАДРИ_ФОТО_П = null;      // Map: фото → проміс розкодованого кадру; є лише поки оцінка будує перелік
async function розкодуватиФотоП(ф){
  const бл = await (await fetch('data:' + (ф.тип || 'image/jpeg') + ';base64,' + ф.дані)).blob();
  return createImageBitmap(бл);
}
function прогрітиКадриП(фото){
  звільнитиКадриП();
  КАДРИ_ФОТО_П = new Map();
  for (const ф of фото){
    const п = розкодуватиФотоП(ф);
    п.catch(()=>{});             // збій розкодування не губиться: `кадрФотоП` розкодує сам і скаже про нього
    КАДРИ_ФОТО_П.set(ф, п);
  }
}
function звільнитиКадриП(){
  const к = КАДРИ_ФОТО_П; КАДРИ_ФОТО_П = null;
  if (к) for (const п of к.values()) п.then(бм=>{ if (бм && бм.close) бм.close(); }, ()=>{});
}
/* {бм, свій}: `свій` — кадр розкодовано тут і закрити його має викликач; кадр з кешу закриває `звільнитиКадриП` */
async function кадрФотоП(ф){
  const п = КАДРИ_ФОТО_П && КАДРИ_ФОТО_П.get(ф);
  if (п){ try{ return {бм: await п, свій: false}; }catch(e){ /* розкодуємо сами нижче */ } }
  return {бм: await розкодуватиФотоП(ф), свій: true};
}
async function пікселіРечіП(ф, рамка, безПоля, сторона){
  try{
    const {бм, свій} = await кадрФотоП(ф);
    const W = бм.width, H = бм.height;
    const р = рамка || ДОВІДНИК.показ.повний_кадр;
    const дx = рамка && !безПоля ? (р.право - р.ліво) * ПОЛЕ_РАМКИ_П : 0, дy = рамка && !безПоля ? (р.низ - р.верх) * ПОЛЕ_РАМКИ_П : 0;
    const лів = Math.max(0, р.ліво - дx), вер = Math.max(0, р.верх - дy), пра = Math.min(1000, р.право + дx), низ = Math.min(1000, р.низ + дy);
    const x0 = Math.round(лів / 1000 * W), y0 = Math.round(вер / 1000 * H);
    const ш = Math.max(1, Math.round((пра - лів) / 1000 * W));
    const в = Math.max(1, Math.round((низ - вер) / 1000 * H));
    const ядро = рамка && !безПоля ? {ліво: Math.round((р.ліво - лів) / (пра - лів) * 1000), верх: Math.round((р.верх - вер) / (низ - вер) * 1000),
                          право: Math.round((р.право - лів) / (пра - лів) * 1000), низ: Math.round((р.низ - вер) / (низ - вер) * 1000)} : null;
    const к = Math.min(1, (сторона || МАКС_СТОРОНА_ВИМІРУ_П) / Math.max(ш, в));
    const w = Math.max(1, Math.round(ш * к)), h = Math.max(1, Math.round(в * к));
    const кан = document.createElement('canvas'); кан.width = w; кан.height = h;
    const ктх = кан.getContext('2d'); ктх.imageSmoothingEnabled = true; ктх.imageSmoothingQuality = 'high';
    ктх.drawImage(бм, x0, y0, ш, в, 0, 0, w, h);
    if (свій && бм.close) бм.close();
    const rgba = ктх.getImageData(0, 0, w, h).data;
    const rgb = new Uint8Array(w * h * 3);
    for (let i = 0, j = 0; i < rgba.length; i += 4, j += 3){ rgb[j] = rgba[i]; rgb[j+1] = rgba[i+1]; rgb[j+2] = rgba[i+2]; }
    return Object.assign({дані: байтиВБ64урл(rgb), ширина: w, висота: h}, ядро ? {ядро} : {});
  }catch(e){
    /* не мовчки: без пікселів вердикт стоїть на слові кольору стилістки, і це сказано в ньому */
    console.warn('пікселі речі з фото не прочитались:', e);
    return null;
  }
}
