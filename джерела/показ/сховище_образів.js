/* СХОВИЩЕ ОБРАЗІВ І «УСІ ОБРАЗИ» — логіка (перепис екрана, частина 7ґ; доти — вбудований скрипт `показ.html`).
   Образи лишаються на телефоні й згруповані за випадком; повторне судження — новий запис вердикту. Вузлів тут
   нема: перелік плиток — модель `БІБЛІОТЕКА_П`, її малює `екран/усі_образи.js` на ім'я `показатиБібліотеку()`;
   збій каже кодом виду, слід лишає `збійЖінціП(null, …)`. */
/* ── сховище образів ── */
/* КЛЮЧ ЗАПИСУ — ІД ПРОГОНУ (наряд Л-7; повний розбір — біля `новийІдПрогону`).
   `ключСтарогоПрогонуП` лишається рівно тим, чим був, і потрібен для записів, зроблених
   збірками до іда: інакше вони або зникли б зі «Усіх образів», або кожне
   збереження кадру плодило б їм дубль. Той самий ключ в'яже й вердикти тих
   давніх прогонів — так, як в'язав.
   ПОВТОРНЕ ЗБЕРЕЖЕННЯ ТОГО САМОГО ПРОГОНУ І ДАЛІ ЗАМІЩАЄ ЙОГО ЗАПИС, і це не
   затирання: `зберегтиОбраз` кличеться з `рендер`, із приміряння і з відкритого
   з бібліотеки образу — усі три рази це ОДИН прогін, який дописує свої кадри. */
const ключСтарогоПрогонуП = з => [(з || {}).збірка || '?', (з || {}).розклад ?? '?', (з || {}).профіль || ''].join('\u00b7');
const ключЗаписуОбразуП = П => ((П && П.прогін) ? String(П.прогін) : ключСтарогоПрогонуП(П));
/* ── ЗАПИС МУСИТЬ ДОЇХАТИ ДО ЧИТАННЯ (наряд Л-8, 27.09.2026) ───────────────
   `рендер` кличе `зберегтиОбраз` і НЕ чекає на нього (чекати нема чого: картки
   вже на екрані). Обіцянка лишалась нічия, тож «Усі образи», відкриті одразу
   після збору, читали сховище паралельно з незавершеним `put` — гонка, у якій
   список міг вийти без щойно зібраного прогону. Тепер остання обіцянка стоїть
   тут, і читач бібліотеки на неї чекає. Відмова запису читання не валить: її
   вже спіймав `catch` нижче, а `оновитиБібліотеку` покаже те, що в сховищі є. */
let ЗАПИС_ОБРАЗУ_П = null;
function зберегтиОбраз(){
  ЗАПИС_ОБРАЗУ_П = (async () => {
    try{
      if (typeof П === 'undefined' || !П || !П.картки || !П.картки.length) return;
      const d = await дб();
      /* `прогін` стоїть ПОЛЕМ запису, а не лише ключем: по ньому бібліотека в'яже
         вердикти, а читати його з ключа означало б вгадувати, що цей ключ — ід, а
         не давній `збірка·розклад·профіль`. */
      /* Рядок випадку — лише `випадок_рядок`, який пише шов збирання: поле `випадок` ніс пакет стенда з хеша адреси,
         а його показ більше не читає (рішення 11824). */
      const запис = {ключ: ключЗаписуОбразуП(П), прогін: (П.прогін || null), час: new Date().toISOString(),
                     випадок: П.випадок_рядок || '', П: JSON.parse(JSON.stringify(П))};
      await tx(d, 'образи', 'readwrite', s => s.put(запис, запис.ключ));
      завершитиДіюЯдра('зберегтиОбраз', запис.ключ);
    }catch(e){ показатиЗбійЗапису('not_saved', e); }
  })();
  return ЗАПИС_ОБРАЗУ_П;
}
async function усіОбрази(){
  const d = await дб();
  return new Promise((рез, від) => { const r = d.transaction('образи').objectStore('образи').getAll(); r.onsuccess = () => рез(r.result || []); r.onerror = () => від(r.error); });
}

/* ── «Усі образи»: модель переліку ──
   `БІБЛІОТЕКА_П.стан`: '' — є що показати, 'читається', 'порожньо' чи код виду збою; `групи` — [{нагода, плитки}],
   `плитки` — ті самі плитки рядом, номер у ньому — ід кнопки на екрані (`біб-образ-<н>`) і вхід `відкритиОбразБібліотекиП`.
   Плитка — {запис, поз, картка, кадр, річ, дата, решта, вердикт, записів}: дані, слова складає малювач; `запис` —
   номер запису сховища в `ЗАПИСИ_БІБЛІОТЕКИ_П` (сам запис із прогоном у плитку не кладемо: відкриття бере його
   просто з прочитаного переліку). */
let БІБЛІОТЕКА_П = {стан: '', групи: [], плитки: []};
let ЗАПИСИ_БІБЛІОТЕКИ_П;
function плиткаБібліотекиП(о, номер, карт, i, вердикти){
  const П_ = о.П || {};
  /* ── ВЕРДИКТИ ЦЬОГО ПРОГОНУ, А НЕ ОДНОЙМЕННОГО (наряд Л-7) ─────────────
     Доти в'язка йшла за `збірка·розклад·профіль` — ключем, який у двох
     зборах з однаковою перестановкою рук ОДИН. Тобто плитка нового прогону
     несла вердикт старого (а старого запису вже й не було — його затер
     `put`), і жінка читала «не вдягну» під образом, якого не бачила.
     Прогін з ідом бере ЛИШЕ записи з тим самим ідом. Давній запис (іда не
     мав) бере лише вердикти, у яких іда теж НЕМА: вердикт свіжого збору на
     нього не сідає, а його власні лишаються при ньому. */
  const ід = П_.прогін ? String(П_.прогін) : null;
  const кл = ключСтарогоПрогонуП(П_);
  const вв = вердикти.filter(в => (ід ? String(в.прогін || '') === ід
                                      : (!в.прогін && ключСтарогоПрогонуП(в) === кл))
                                 && +в.позиція === i + 1)
                     .sort((a, b) => String(a.час).localeCompare(String(b.час)));
  /* ── МІНІАТЮРА — ТОЙ ОБРАЗ, А НЕ ПЕРША РІЧ (ділянка 6/8, 26.09.2026) ──
     Бібліотека брала `речі.find(x => x.фото)` — тобто фото ОДНІЄЇ речі з
     крамниці, першої, що трапилась. А в картці вже лежить `картинка`:
     приміряний кадр, який жінка судила (або її власний файл чи адреса). У
     списку «Усі образи» через це стояли чотири схожі сукні замість
     чотирьох різних образів — образ на вигляд не відрізнявся від сусіднього,
     і по знімку його не знайти.
     `blob:` НЕ БЕРЕМО: `URL.createObjectURL` живе рівно до перезавантаження
     вкладки, а бібліотека читається саме після нього — мертве посилання дало
     б порожню рамку там, де є справне фото речі. Data URI й адреса
     переживають (їх зберігає той самий `зберегтиОбраз`). */
  /* кадр генератора — лише повернений (`кадрПоказуП`): збережений до повернення не показується */
  const кадрКартки = кадрПоказуП(карт);
  const кадр = (кадрКартки && !/^blob:/i.test(кадрКартки)) ? кадрКартки : null;
  const річ = (карт.речі || []).find(x => x.фото && !(карт.фото_не_ті || []).includes(x.id)) || null;
  return {запис: номер, поз: i, картка: карт, кадр, річ,
          дата: String(о.час || '').slice(0, 10), решта: String(о.випадок || '').split(' \u00b7 ').slice(1).join(' \u00b7 '),
          вердикт: вв.length ? вв[вв.length - 1] : null, записів: вв.length};
}
async function оновитиБібліотеку(){
  БІБЛІОТЕКА_П = {стан: 'читається', групи: [], плитки: []}; показатиБібліотеку();
  let образи, вердикти;
  const збій = (вид, e) => { збійЖінціП(null, вид, e); БІБЛІОТЕКА_П = {стан: вид, групи: [], плитки: []}; показатиБібліотеку(); };
  try{ await ЗАПИС_ОБРАЗУ_П; }catch(e){ збійЖінціП(null, 'not_saved', e); }   /* запис ловить свої збої сам; це — на решту */
  try{ образи = await усіОбрази(); }
  catch(e){ збій('library_unreadable', e); return; }
  try{ вердикти = await усіВердикти(); }
  catch(e){ збій('journal_unreadable', e); return; }
  if (!образи.length){ БІБЛІОТЕКА_П = {стан: 'порожньо', групи: [], плитки: []}; показатиБібліотеку(); оновитиЖурнал(); return; }
  образи.sort((a, b) => String(b.час).localeCompare(String(a.час)));
  ЗАПИСИ_БІБЛІОТЕКИ_П = образи;
  /* ЗАГОЛОВОК ГРУПИ — ПЕРШИЙ ШМАТОК РЯДКА ВИПАДКУ, а не назва з даних: шматок складає код — підпис довідника,
     обрізок її слів чи рядок мосту, а в записі з пакета стенда — його поле `випадок`, чийого писача показ не знає. */
  const заНагодою = new Map();
  образи.forEach(о => { const н = String(о.випадок || 'Без випадку').split(' \u00b7 ')[0] || 'Без випадку';
                        if (!заНагодою.has(н)) заНагодою.set(н, []); заНагодою.get(н).push(о); });
  const плитки = [], групи = [];
  for (const [нагода, список] of заНагодою){
    const свої = [];
    for (const о of список) ((о.П || {}).картки || []).forEach((карт, i) => свої.push(плиткаБібліотекиП(о, образи.indexOf(о), карт, i, вердикти)));
    групи.push({нагода, від: плитки.length, плитки: свої}); плитки.push(...свої);
  }
  БІБЛІОТЕКА_П = {стан: '', групи, плитки}; показатиБібліотеку();
  оновитиЖурнал();
  завершитиДіюЯдра('бібліотека', null);
}
/* Дотик плитки: прогін запису стає чинним показом на картці плитки. Запис не розгорнувся — код збою в стан переліку
   (перелік лишається, як був). */
function відкритиОбразБібліотекиП(н){
  const пл = БІБЛІОТЕКА_П.плитки[н]; if (!пл) return;
  try{
    const о = ЗАПИСИ_БІБЛІОТЕКИ_П[пл.запис];
    П = JSON.parse(JSON.stringify(о.П)); П.випадок_рядок = о.випадок || П.випадок_рядок || '';
    рендер();
    /* Новий показ стає на першу картку; явний вибір бібліотечної плитки — після нього. */
    показатиОбраз(пл.поз);
    /* ОЦІН-1: вердикти цього прогону лежать у сховищі, а `В` після відкриття порожнє — тож лічильник «оцінено N з M»
       і дописування того самого запису мусять їх підхопити */
    відновитиВердиктиПрогону().catch(e => показатиЗбійЗапису('journal_unreadable', e));
  }catch(e){
    збійЖінціП(null, 'library_unreadable', e);
    БІБЛІОТЕКА_П = {...БІБЛІОТЕКА_П, стан: 'library_unreadable'}; показатиСтанБібліотеки();
  }
}
async function відновитиВердиктиПрогону(){
  const р = П; if (!р || !(р.картки || []).length) return;
  const зап = await усіВердиктиЗКлючами();
  if (П !== р) return;                      /* тим часом відкрили інший прогін */
  const ід = р.прогін ? String(р.прогін) : null, кл = ключСтарогоПрогонуП(р);
  р.картки.forEach((карт, j) => {
    if (карт.збій) return;
    const в0 = В[j];
    if (в0 && (в0.запис_ключ != null || в0.верд)) return;     /* цей прогін уже на екрані зі своїм станом */
    const вв = зап.filter(({зап: z}) => записЖінкиП(z) && +z.позиція === j + 1
                                         && (ід ? String(z.прогін || '') === ід : (!z.прогін && ключСтарогоПрогонуП(z) === кл)))
                  .sort((a, b) => String(a.зап.час).localeCompare(String(b.зап.час)));
    if (!вв.length) return;
    const ост = вв[вв.length - 1];
    відновитиСтанКарткиП(j, ост.зап, ост.ключ);
  });
  показатиПейджер();
}
