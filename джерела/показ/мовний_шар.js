/* Пачки викликів шару для `питаннямиП`: записи та стан кожного повідомлення.
   Лише переклади (і переклад напису розкривача) лягають у `ПАМ_ЯТЬ_ПИТАНЬ_П`. */
async function питатиПачкамиП(елементи, де){
  const записи = [], стани = new Map();
  /* ПАЧКИ — ТЕЖ РАЗОМ (Ш-1): у кожної пачки свої питання і свій виклик, і
     відповідь однієї не потрібна іншій; записи й пам'ять — у порядку пачок */
  const пачки = [];
  for (let п0 = 0; п0 < елементи.length; п0 += ПИТАНЬ_НА_ВИКЛИК_П) пачки.push(елементи.slice(п0, п0 + ПИТАНЬ_НА_ВИКЛИК_П));
  const виклик = (пачка, суфікс) =>
    повідомленнямП(Object.fromEntries(пачка.map(([, кв, пов]) => [кв, пов])),
                   (де ? де + '.' : '') + 'code_unknowns' + суфікс);
  const відповіді = await Promise.all(пачки.map(пачка => виклик(пачка, '')));
  /* Повтор пропущених ключів уже виконує повідомленнямП. */
  for (let н = 0; н < пачки.length; н++){
    const мп = відповіді[н];
    записи.push(...мп.записи);
    пачки[н].forEach(([к_, кв, пов]) => {
      const т_ = мп.тексти[кв];
      const свої = (мп.заяви || []).filter(р => р.повідомлення === кв);
      const перекладено = !!т_ && свої.length > 0 && свої.every(р => р.стан === 'translated');
      стани.set(к_, {текст: безМашинногоСліду(т_ || НАПИС_БЕЗ_ШАРУ_П[пов.kind] || НАПИС_БЕЗ_ТЕКСТУ_П),
        стан: перекладено ? 'translated' : 'fallback'});
      if (!перекладено) return;
      if (ПАМ_ЯТЬ_ПИТАНЬ_П.size >= СТЕЛЯ_ПАМ_ЯТІ_ПИТАНЬ_П) ПАМ_ЯТЬ_ПИТАНЬ_П.delete(ПАМ_ЯТЬ_ПИТАНЬ_П.keys().next().value);
      ПАМ_ЯТЬ_ПИТАНЬ_П.set(к_, безМашинногоСліду(т_));
    });
  }
  return {записи, стани};
}
/* ВНУТРІШНЯ МОВА — ЛАТИНИЦЕЮ (П-3): з шаром функціональна модель пише англійською (п.12),
   жінці — українською, кирилицею. Текст, у якому є літери і ВСІ вони латинські, шар їй не
   написав. Слів код не читає — лише письмо літер: бренд чи «°C» в українському реченні
   самою латиницею не є. */
/* Частка латинських слів виявляє чужомовну прозу навіть з українськими вставками.
   Джерельні слова з набору свої вилучаються з обох частин дробу.
   Сам регістр чи мова входу не засвідчують походження назви. */
const ЧАСТКА_ЧУЖОЇ_П = 0.3;
function словаП(т){ return String(т || '').match(/[\p{L}][\p{L}\p{N}'’\-]*/gu) || []; }
function латинськеСловоП(с){
  const л = с.match(/\p{L}/gu) || [];
  return л.length > 0 && л.every(x => /\p{Script=Latin}/u.test(x));
}
function чужоюМовоюП(т, свої){
  /* Одна латинська літера («°C», «x» у «2x») — знак, а не слово: мови не свідчить, і «+12 °C» не чужа мова */
  const слова = словаП(т).filter(с => !(свої && свої.has(с.toLowerCase())) && !(с.length === 1 && латинськеСловоП(с)));
  if (!слова.length) return false;
  return слова.filter(латинськеСловоП).length / слова.length > ЧАСТКА_ЧУЖОЇ_П;
}
/* Лише джерельні слова входу: його мова не доводить і не скасовує походження назви.
   Назви каталогу передає їхній читач; інше джерело — її дослівний ввід. */
function своїВходуП(вхід, назви){
  const джерельні = new Set([...своїСловаЧатуП(), ...(назви || [])]);
  return new Set(словаП(вхід).map(с => с.toLowerCase()).filter(с => джерельні.has(с)));
}
/* Латинські слова, які код сам поклав у рядок: значення заяв і самі коди. */
function своїСловаП(повідомлення){
  const свої = new Set();
  const зібрати = v => {
    if (v === null || v === undefined) return;
    if (Array.isArray(v)) return v.forEach(зібрати);
    if (typeof v === 'object') return Object.values(v).forEach(зібрати);
    словаП(v).forEach(с => свої.add(с.toLowerCase()));
  };
  for (const п of Object.values(повідомлення || {})){
    for (const з of ((п && п.statements) || [])){
      if (з && з.code) свої.add(String(з.code).toLowerCase());
      зібрати(з && з.values);
    }
  }
  return свої;
}
/* Зайва латинка й змішане письмо перевіряються також у переважно українській прозі.
   Залишки йдуть у повтор точними словами; невиправлене знімається реченням.
   Законні джерельні слова передаються набором свої,
   а відхилення зберігаються в записах для звіту. */
const ЗАКОННА_ЛАТИНКА_П = new Set(['den']);
/* БИТІ ЗНАКИ Й ЛІТЕРИ НЕ З УКРАЇНСЬКОЇ АБЕТКИ: «тонка полі† пряжка», «мохо��ий»,
   «пэчворковим» — 3 картки. Це теж факт письма, а не слово (п.12): знак заміни U+FFFD і «†» посеред слова,
   «ы э ё ъ» в українському тексті. Ловить той самий сторож — отже той самий повтор і те саме зняття
   відрізка; слова, які код сам поклав у рядок (`свої`: назва крамниці), — законні. */
const БИТИЙ_ЗНАК_П = /[\u2020\uFFFD]/u, НЕ_УКРАЇНСЬКА_ЛІТЕРА_П = /[ыэёъЫЭЁЪ]/u;
/* КАРТКА-СЛОВА: слово бере й цифри ПЕРЕД літерами. Інакше «14oz» і «14k» сторож бачив би як «oz» і «k» —
   коротші за три літери, тобто законні, — і одиниця латиницею лишалась би на картці. Літери,
   приклеєні до числа, — уже не скорочення, а слово латиницею: довжина рахується з цифрами. */
const СЛОВО_З_БИТИМ_П = /\p{N}*[\p{L}\u2020\uFFFD][\p{L}\p{N}'’\-\u2020\uFFFD]*/gu;
function письмоЧастиниП(ч){
  const л = ч.match(/\p{L}/gu) || [];
  const лат = л.filter(х => /\p{Script=Latin}/u.test(х)).length;
  return !л.length ? '' : лат === л.length ? 'лат' : лат === 0 ? 'інше' : 'змішане';
}
/* КАРТКА-СЛОВА: на картках усіх рук скорочення законне лише як джерельне слово
   у наборі `свої`. Самі великі літери не свідчать, що «піна EVA» прийшла від крамниці
   (`безСкорочень` у наборі `свої`, див. `законніКарткиП`). */
function латинськіЗалишкиП(т, свої){
  const вих = [], скорочення = !(свої && свої.безСкорочень);
  for (const с of (String(т || '').match(СЛОВО_З_БИТИМ_П) || [])){
    if (свої && (свої.has(с.toLowerCase()) || свої.has(с.toLowerCase().replace(/^\p{N}+/u, '')))) continue;
    if (БИТИЙ_ЗНАК_П.test(с) || НЕ_УКРАЇНСЬКА_ЛІТЕРА_П.test(с)){ вих.push(с); continue; }
    const ч = с.split('-').filter(Boolean).map(х => [х, письмоЧастиниП(х)]);
    const чиста = ч.length > 0 && ч.every(([, п]) => п === 'лат');
    const чужа = чиста
      ? ч.some(([х]) => х.length >= 3 && !ЗАКОННА_ЛАТИНКА_П.has(х.toLowerCase())
                      && !(свої && свої.has(х.toLowerCase()))
                      && !/^[0-9a-f]{6}$/i.test(х) && !(скорочення && /^\p{N}*\p{Lu}{2,4}$/u.test(х)))
      : ч.some(([, п]) => п === 'змішане') || ч.some(([х, п]) => п === 'лат' && х.length >= 2);
    if (чужа) вих.push(с);
  }
  return вих;
}
