async function повідомленнямП(повідомлення, де, повтор){
  const ключі = Object.keys(повідомлення || {}).filter(к => повідомлення[к] && повідомлення[к].kind);
  if (!ключі.length) return {тексти: {}, записи: []};
  const вхід = Object.fromEntries(ключі.map(к => [к, повідомлення[к]]));
  const памКлюч = JSON.stringify(вхід);
  if (!повтор && ПОВІДОМЛЕННЯ_В_ДОРОЗІ_П.has(памКлюч)){
    const р = await ПОВІДОМЛЕННЯ_В_ДОРОЗІ_П.get(памКлюч).catch(() => null);
    if (р) return Object.assign({}, р, {тексти: Object.assign({}, р.тексти), записи: [{
      напрям: 'out_messages', де, модель: МОДЕЛЬ_МОВИ_П, коли: new Date().toISOString(),
      спільний_виклик: true, мс: 0, вхід, вихід: р.тексти, заяви: р.заяви}]},
                                р.чужою ? {чужою: р.чужою.slice()} : {}, р.без_слів ? {без_слів: р.без_слів.slice()} : {});
  }
  if (ПАМ_ЯТЬ_ПОВІДОМЛЕНЬ_П.has(памКлюч)){
    const р = ПАМ_ЯТЬ_ПОВІДОМЛЕНЬ_П.get(памКлюч);
    return {...р, записи: [{напрям: 'out_messages', де, модель: МОДЕЛЬ_МОВИ_П,
      коли: new Date().toISOString(), кеш: true, мс: 0, вхід, вихід: р.тексти, заяви: р.заяви}]};
  }
  if (!повтор && ПАМ_ЯТЬ_ЧУЖИХ_П.has(памКлюч)){
    const р = ПАМ_ЯТЬ_ЧУЖИХ_П.get(памКлюч);
    return {тексти: Object.assign({}, р.тексти), записи: [], чужою: р.чужою.slice(),
            ...(р.без_слів ? {без_слів: р.без_слів.slice()} : {})};
  }
  const обіцянка = повідомленнямМоделлюП(вхід, ключі, памКлюч, де, повтор);
  if (повтор) return обіцянка;
  ПОВІДОМЛЕННЯ_В_ДОРОЗІ_П.set(памКлюч, обіцянка);
  try{ return await обіцянка; }finally{ ПОВІДОМЛЕННЯ_В_ДОРОЗІ_П.delete(памКлюч); }
}
async function повідомленнямМоделлюП(вхід, ключі, памКлюч, де, повтор, помилки){
  /* Місце показу й ключ заяви різні: перестановка відповіді не переставляє предмети. */
  const вих = {тексти: {}, записи: [], заяви: [], виклики_договору: []};
  const запис = {напрям: 'out_messages', де: де || '', модель: МОДЕЛЬ_МОВИ_П,
                 коли: new Date().toISOString(), вхід};
  const почато = Date.now();
  try{
    let р1 = await містП('мова', {повідомлення: вхід, ...(помилки ? {помилки_повідомлень: помилки} : {})});
    if (!р1 || р1.помилка) throw new Error((р1 && р1.помилка) || 'bridge_no_prompt');
    запис.розмітка = р1.розмітка;
    вих.заяви = (р1.розмітка || []).map(р => ({...р,
      текст: ТЕКСТИ_ЗА_КЛЮЧЕМ_П.get(р.ключ) || null,
      стан: ТЕКСТИ_ЗА_КЛЮЧЕМ_П.has(р.ключ) ? 'translated' : 'missing_text'}));
    const потрібні = вих.заяви.filter(р => р.стан === 'missing_text');
    if (потрібні.length && потрібні.length !== вих.заяви.length){
      const пов = {};
      for (const р of потрібні){
        пов[р.повідомлення] ||= {kind: р.вид, statements: []};
        пов[р.повідомлення].statements.push(...р.заяви);
      }
      р1 = await містП('мова', {повідомлення: пов});
    }
    if ((р1.незнайомі || []).length) запис.незнайомі = р1.незнайомі;
    if (МОДЕЛЬ_МОВИ_П && потрібні.length && р1.промпт){
      if (р1.вибірка) запис.вибірка = р1.вибірка;
      const відповідь = await модельМовиП(р1.промпт, р1.вибірка, запис);
      запис.відповідь_моделі = відповідь;
      const запит = {розмітка_повідомлень: р1.розмітка, відповідь_моделі: відповідь};
      вих.виклики_договору.push(запит);
      const р2 = await містП('мова', запит);
      if (!р2 || р2.помилка || !р2.заяви) throw new Error((р2 && р2.помилка) || 'bridge_no_answer');
      const прийняті = new Map(р2.заяви.map(р => [р.ключ, р]));
      вих.заяви = вих.заяви.map(р => прийняті.has(р.ключ)
        ? {...прийняті.get(р.ключ), повідомлення: р.повідомлення} : р);
      if (р2.причина) запис.причина = р2.причина;
      if (р2.помилки && р2.помилки.length) запис.помилки = р2.помилки;
      if ((р2.нотатки || []).length) запис.нотатки = р2.нотатки;
      запис.зайві_ключі = р2.зайві_ключі || [];
    }else if (!МОДЕЛЬ_МОВИ_П) запис.причина = 'no_language_model';
  }catch(e){
    запис.причина = МОДЕЛЬ_МОВИ_П ? 'layer_failed: ' + String((e && e.message) || e) : 'no_language_model';
    запис.помилка_моста = String((e && e.message) || e);
    if (!вих.заяви.length) вих.заяви = Object.entries(вхід).flatMap(([к, п]) =>
      (п.statements || []).map(з => ({ключ: з.key || null, повідомлення: к, вид: п.kind,
        заяви: [з], текст: null, стан: 'missing_text'})));
  }
  Object.assign(вих, перевіритиКінцевуВідповідьШаруП(вих));
  запис.чужою = вих.чужою;
  запис.заяви = вих.заяви.map(р => ({...р}));
  запис.без_відповіді = вих.заяви.filter(р => р.стан === 'missing_text').map(р => р.ключ);
  вих.записи.push(запис);
  const відсутні = вих.заяви.filter(р => р.стан !== 'translated');
  for (const запит of вих.виклики_договору) запит.відхилені_тексти = відсутні.map(р => р.ключ);
  if (!повтор && МОДЕЛЬ_МОВИ_П && відсутні.length){
    const ще = {};
    for (const р of відсутні){
      ще[р.повідомлення] ||= {kind: р.вид, statements: []};
      ще[р.повідомлення].statements.push(...р.заяви);
    }
    const р = await повідомленнямМоделлюП(ще, Object.keys(ще), '', (де || '') + '.retry', true,
      [...(запис.помилки || []), ...відсутні.map(з => ({де: з.ключ, що: з.стан}))]);
    const разом = await злитиВідповідіШаруП([вих, р]);
    const заКлючем = new Map((разом.заяви || []).map(з => [з.ключ, з]));
    // Записи з пам'яті не були викликами моделі й залишаються у своїх місцях.
    вих.заяви = вих.заяви.every(з => з.ключ === null) ? разом.заяви
      : вих.заяви.map(з => заКлючем.has(з.ключ) ? {...заКлючем.get(з.ключ), повідомлення: з.повідомлення} : з);
    вих.виклики_договору = разом.виклики_договору;
    вих.чужою = [...new Set(вих.заяви.filter(з => СТАНИ_НЕ_МОВИ_П.includes(з.стан)).map(з => з.повідомлення))];
    вих.записи.push(...р.записи);
  }
  Object.assign(вих, перевіритиКінцевуВідповідьШаруП(вих));
  /* Сталий напис інтерфейсу позначає кожну заяву без тексту, включно з частковою відповіддю. */
  for (const р of вих.заяви){
    if (['stylist', 'journal'].includes((р.заяви[0] || {}).recipient)) continue;
    р.показано = true;
    if (р.стан === 'translated' && !ТЕКСТИ_ЗА_КЛЮЧЕМ_П.has(р.ключ)){
      if (ТЕКСТИ_ЗА_КЛЮЧЕМ_П.size >= СТЕЛЯ_ПАМ_ЯТІ_ПОВІДОМЛЕНЬ_П)
        ТЕКСТИ_ЗА_КЛЮЧЕМ_П.delete(ТЕКСТИ_ЗА_КЛЮЧЕМ_П.keys().next().value);
      ТЕКСТИ_ЗА_КЛЮЧЕМ_П.set(р.ключ, р.текст);
    }
    const т = р.стан === 'translated' ? р.текст : (НАПИС_БЕЗ_ШАРУ_П[р.вид] || НАПИС_БЕЗ_ТЕКСТУ_П);
    вих.тексти[р.повідомлення] = [вих.тексти[р.повідомлення], т].filter(Boolean).join(' ');
  }
  /* Жодна заява рядка не перекладена — сталий напис місця: картка ховає його під згорнутий
     рядок, а «Заміни не знайдено — натисни ще раз…» чи «Оцінити не вдалось…» лишаються фактом показу (п.12). */
  for (const к of ключі){
    const свої = вих.заяви.filter(р => р.повідомлення === к && р.показано);
    if ((свої.length && свої.every(р => р.стан !== 'translated'))
        || (!(к in вих.тексти) && !вих.заяви.some(р => р.повідомлення === к)))
      вих.тексти[к] = НАПИС_БЕЗ_ШАРУ_П[(вхід[к] || {}).kind] || НАПИС_БЕЗ_ТЕКСТУ_П;
    else if (!(к in вих.тексти)) вих.тексти[к] = '';
  }
  запис.мс = Date.now() - почато;
  запис.вихід = {...вих.тексти};
  запис.показ = вих.заяви.map(р => ({ключ: р.ключ, повідомлення: р.повідомлення,
    стан: р.стан, текст: р.текст, показано: !!р.показано}));
  if (вих.заяви.length && вих.заяви.every(р => р.стан === 'translated')){
    if (ПАМ_ЯТЬ_ПОВІДОМЛЕНЬ_П.size >= СТЕЛЯ_ПАМ_ЯТІ_ПОВІДОМЛЕНЬ_П)
      ПАМ_ЯТЬ_ПОВІДОМЛЕНЬ_П.delete(ПАМ_ЯТЬ_ПОВІДОМЛЕНЬ_П.keys().next().value);
    ПАМ_ЯТЬ_ПОВІДОМЛЕНЬ_П.set(памКлюч, {тексти: {...вих.тексти}, заяви: вих.заяви});
  }
  return вих;
}
/* Рядок діагнозу на кожен виклик шару: де (рука — на початку, тож рядок іде в її
   `діагноз_руки`), модель, час, скільки текстів змінено і які лишились вхідними та чому
   (без стелі — п.9 аудит/ПРОДУКТ.md). Повний запис виклику — у `мова_шару` картки. */
/* Рядок повідомлення складає мовна модель з кодів, не показ із людських слів.
   Готові записи шару зберігають вхід, вихід і причину відмови для звіту;
   екран отримує переклад або шаблон відповідного виду. */
function рядкиШаруП(записи){
  return (записи || []).map(з => {
    const ключі = Object.keys(з.вхід || {});
    /* повідомлення внутрішньою мовою (Ч-1): «змінено» там ніщо не значить — вхід не текст,
       а коди; рахується, на скільки ключів модель ВІДПОВІЛА текстом */
    const повідомленнями = з.напрям === 'out_messages';
    const змінено = повідомленнями ? (з.заяви || []).filter(р => р.стан === 'translated').length
      : ключі.filter(к => (з.вихід || {})[к] !== з.вхід[к]).length;
    return (з.де ? з.де + ' · ' : '') + 'layer · dir=' + з.напрям + ' · model=' + з.модель + ' · ms=' + з.мс
      + (повідомленнями ? ' · messages=' + ключі.length + ' · said=' : ' · texts=' + ключі.length + ' · changed=')
      + змінено
      + ((з.незнайомі || []).length ? ' · unknown_codes=' + з.незнайомі.join(',') : '')
      + ((з.чужою || []).length ? ' · foreign=' + з.чужою.join(',') : '')
      + ((з.без_відповіді || []).length
         ? (повідомленнями ? ' · no_line=' : ' · kept_input=') + з.без_відповіді.join(',') + ' · reason=' + з.причина
         : '')
      + ((з.нотатки || []).length ? ' · notes=' + з.нотатки.join(';') : '');
  });
}
/* Тексти картки перекладаються разом; поля речей адресуються їхніми ключами.
   Повідомлення й питання мають окремі незалежні виклики,
   а записи всіх маршрутів лишаються в картці для звіту. */
/* Готових ТЕКСТІВ на картці вже нема: усе, що доти складав код, їде повідомленнями нижче
   (Ч-1, аудит/ПРОДУКТ.md п.12). Перелік лишається порожнім навмисно — шов готових текстів потрібен
   опису, «як це носити», назвам вигаданих речей і питанням, які пише не код, а моделі. */
const ПОЛЯ_КАРТКИ_ЖІНЦІ = [];
/* Поля картки, які Python віддає ПОВІДОМЛЕННЯМ внутрішньою мовою (Ч-1, п.12): речення з них
   складає мовна модель тим самим викликом, що й `пом'якшення` під її річчю. */
const ПОВІДОМЛЕННЯ_КАРТКИ = ['схема_жінці', 'нагода_жінці', 'носіння_жінці', 'матеріал_жінці',
                             'неповний', 'дібрав_код', 'замінено', 'кадр_не_відкрився', 'без_опису'];
/* Готових ТЕКСТІВ біля речі теж уже нема: `чому_додав` і `чому_без_фото` приїжджають
   повідомленнями (Ч-1, п.12). Перелік лишається для назв, які пише функціональна модель. */
const ПОЛЯ_РЕЧІ_ЖІНЦІ = [];
/* Поля речі, які Python віддає ПОВІДОМЛЕННЯМ внутрішньою мовою, а не текстом (Ч-1, п.12):
   речення з них складає мовна модель тим самим викликом, що й решту картки. */
const ПОВІДОМЛЕННЯ_РЕЧІ = ['пом_якшення', 'чому_без_фото', 'чому_додав'];
/* ── РЕЧІ КАРТКИ ДЛЯ ПЕРЕКЛАДАЧКИ (ПЕРЕКЛАД-34) ─────────────────────
   Перекладачка, що бачить лише англійські тексти, бере вид речі з англійського слова: «plimsolls» →
   «еспадрильї» при «Кеди червоні» на картці, «ankle boots» → «мокасини», рід навмання — «шкіряна клатч».
   Тому разом із текстами їде перелік речей картки: номер (як на картці) і назва з крамниці; назва
   вигаданої речі чи її речі з фото — ключем тексту, який цей виклик і перекладає (назва англійською), а
   в повторі, де цього тексту нема, — уже перекладеною назвою з `перекладено`. Слів показ не читає. */
/* ПЕРЕКЛАД-36: біля речі крамниці — її код кольору й hex (дані, не слова: код кольору
   з них добирає `мовний_шар`, п.18), а коли абзац опису про неї йде своїм текстом (`описиРечейП`), — ключ цього
   тексту (`опис`): шар бачить, який абзац про яку річ. */
function речіШаруП(к, перекладено, описи){
  const речі = (к.речі || []).map((x, і) => {
    if (!x || !x.назва) return null;
    const ключ = 'річ.' + і + '.назва', опис = 'про_річ.' + і;
    const свій = (описи || {})[опис] ? {опис} : {};
    /* вид речі — ключ ядра з укладки: шар дає його кодом, і іменник речі — цього виду */
    const тип = (x.укладка || {}).тип || x.тип_набору || '';
    return (x.вигадана || x.власна)
      ? {н: і + 1, назва: (перекладено || {})[ключ] || x.назва, ключ, ...свій}
      : {н: і + 1, назва: x.назва, ...свій, ...(тип ? {тип} : {}), ...(x.слот ? {слот: x.слот} : {}),
         ...(x.колір ? {колір: x.колір} : {}), ...(x.код_кольору ? {код_кольору: x.код_кольору} : {}),
         ...(x.hex ? {hex: x.hex} : {})};
  }).filter(Boolean);
  // Походження засвідчує код, що читає поля каталогу; відповідь моделі не може додати сюди винятки.
  ДЖЕРЕЛЬНІ_СЛОВА_ШАРУ_П.set(речі, назвиКаталогуКарткиП(к));
  return речі;
}
/* Абзаци опису, що точно збігаються з головою опису речей, ідуть окремими ключами.
   Так шар пов’язує абзац із кодами виду й кольору конкретної речі.
   Переписаний опис, який не збігається з цими абзацами, перекладається цілим. */
function описиРечейП(к, опис){
  const про = (к && к.про_речі) || [];
  if (!про.length || !опис) return null;
  const місце = {};
  (к.речі || []).forEach((x, і) => { if (x && x.id != null) місце[String(x.id)] = і; });
  const абзаци = про.map(р => [місце[String((р || {}).id)], безМашинногоСліду((р || {}).текст, true)]);
  if (абзаци.some(([і, т]) => і === undefined || !т)) return null;
  const голова = абзаци.map(([, т]) => т).join('\n');
  if (опис !== голова && !опис.startsWith(голова + '\n')) return null;
  return {тексти: Object.fromEntries(абзаци.map(([і, т]) => ['про_річ.' + і, т])),
          решта: опис.slice(голова.length + 1)};
}
async function мовоюКарткуП(к, де){
  if (!МОДЕЛЬ_МОВИ_П || !к) return;
  const т = {};
  ПОЛЯ_КАРТКИ_ЖІНЦІ.forEach(п => { if (typeof к[п] === 'string' && к[п]) т[п] = к[п]; });
  /* підпис змінної пари — повідомлення, не текст: він іде нижче, з рештою
     повідомлень картки (Ч-1, п.12) */
  const [опис, задум] = к.мова_ховати_опис ? ['', []]
    : людською({текст: к.опис, як_носити: к.як_носити}, true);
  const описи = описиРечейП(к, опис);
  if (описи){
    Object.assign(т, описи.тексти);
    if (описи.решта) т['опис'] = описи.решта;
  } else if (опис) т['опис'] = опис;
  задум.forEach((р, і) => { т['як_носити.' + і] = р; });
  /* ЗВІТ ВЛАСНИКА (ВМ-3в): оголошені ходи пише функціональна модель англійською (п.12);
     колонка `свідомі` читається власником, тож іде в той самий виклик шару й лягає назад лише
     чистою — що шар не переклав, лишається сирим, доказ не губиться */
  (к.свідомі || []).forEach((х, і) => { if (typeof х === 'string' && х) т['свідомі.' + і] = х; });
  (к.речі || []).forEach((x, і) => ПОЛЯ_РЕЧІ_ЖІНЦІ.forEach(п => {
    if (x && x[п]) т['річ.' + і + '.' + п] = x[п]; }));
  /* НАЗВА ВИГАДАНОЇ РЕЧІ (руки 3–4) І ЇЇ РЕЧІ З ФОТО (П-1): їх пише функціональна модель, з
     шаром — внутрішньою мовою (англійською). Назва крамниці сюди не йде: її склала не модель;
     назва, уже природна українська, від шару вертається без змін. */
  (к.речі || []).forEach((x, і) => { if (x && (x.вигадана || x.власна) && x.назва) т['річ.' + і + '.назва'] = x.назва; });
  /* ПОВІДОМЛЕННЯ ВНУТРІШНЬОЮ МОВОЮ — ОКРЕМИМ ВИКЛИКОМ (Ч-1, п.12): їх не «роблять
     природними», з них СКЛАДАЮТЬ речення, і це інший промпт. Ключ той самий, що поле речі,
     тож картка малює написане шаром; поля, на яке модель не відповіла, на картці просто
     нема, а причина — у записі виклику. */
  /* ── ЗАЯВА ПРО НЕВІДКРИТИЙ КАДР — НАПЕРЕД І ОДНА НА КАРТКУ (Ф-143, п.12) ─────
     Чи відкриється знімок крамниці, видно ЛИШЕ в браузері й лише тоді, коли жінка вже
     дивиться на картку, — а питати модель у ту мить нема коли. Тому заява їде сюди, з
     рештою повідомлень картки, і показ малює готове речення в ту мить, коли ряд кадрів
     речі вичерпався (`підставитиКадр`). Заява ОДНА: про будь-яку річ вона однакова, і
     слати її на кожну річ означало б платити моделі за те саме по вісім разів. */
  if ((к.речі || []).some(x => x && x.фото))
    к.кадр_не_відкрився = {kind: 'no_photo_reason', statements: [{code: ЗАЯВА_КАДР_НЕ_ВІДКРИВСЯ}]};
  const пов = {};
  ПОВІДОМЛЕННЯ_КАРТКИ.forEach(п => { if (к[п] && к[п].kind) пов[п] = к[п]; });
  if (к.змінна_пара && к.змінна_пара.підпис && к.змінна_пара.підпис.kind)
    пов['змінна_пара'] = к.змінна_пара.підпис;
  (к.речі || []).forEach(x => ПОВІДОМЛЕННЯ_РЕЧІ.forEach(п => {
    if (x && x[п] && x[п].kind) пов['річ.' + x.id + '.' + п] = {...x[п],
      statements: (x[п].statements || []).map(з => ({...з,
        item_ids: [...new Set([x.id, ...(з.item_ids || [])].filter(Boolean))]}))}; }));
  /* ТРИ ВИКЛИКИ ШАРУ КАРТКИ — РАЗОМ, А НЕ ОДИН ЗА ОДНИМ (Ш-1). Повідомлення
     картки, «код не знає» і тексти (опис, «як носити», назви) незалежні: жоден не читає
     відповіді іншого, і пишуть вони в різні поля картки. Тому вони йдуть паралельно, а не в ряд у
     кінці ланцюга КОЖНОЇ руки (це були б три-чотири виклики шару підряд перед карткою). Порядок
     записів у `мова_шару` той самий: «код не знає» (дописує сам), повідомлення, тексти. */
  const [мп, , м] = await Promise.all([
    Object.keys(пов).length ? повідомленнямП(пов, де) : {тексти: {}, записи: []},
    питаннямиП(к, де),
    мовоюП(т, де, undefined, речіШаруП(к, undefined, т), undefined, undefined, true)]);
/* Повідомлення картки проходять сторожа в повідомленнямП до запису в поля.
   Відхилений рядок отримує сталий шаблон,
   а його ключ зберігається для діагнозу й звіту. */
  if ((мп.чужою || []).length)
    к.мова_не_перекладено = [...new Set((к.мова_не_перекладено || []).concat(мп.чужою))];
  к.заяви_показу = мп.заяви || [];
  const рядокШару = ключ => (мп.тексти[ключ] || null);
  ПОВІДОМЛЕННЯ_КАРТКИ.forEach(п => { if (п in пов) к[п] = рядокШару(п); });
  if ('змінна_пара' in пов)
    к.змінна_пара = Object.assign({}, к.змінна_пара, {підпис: рядокШару('змінна_пара')});
  (к.речі || []).forEach(x => ПОВІДОМЛЕННЯ_РЕЧІ.forEach(п => {
    if (('річ.' + x.id + '.' + п) in пов) x[п] = рядокШару('річ.' + x.id + '.' + п); }));
  if (мп.записи.length) к.мова_шару = (к.мова_шару || []).concat(мп.записи);
  if (!м.записи.length) return;
/* Неперекладене чи пропущене йде в один повтор тільки своїми ключами.
   Залишки після повтору позначаються в картці для звіту,
   а сира внутрішня мова не виходить жінці. */
  const безВідповіді = (м.записи[0] || {}).без_відповіді || [];
  const дозволені = назвиКаталогуКарткиП(к);
  const своїТ = ключ => new Set([...дозволені, ...своїВходуП(т[ключ], дозволені)]);
  const законніТ = ключ => законніКарткиП(new Set([...своїТ(ключ), ...дозволені]));
  const залишкиТ = ключ => латинськіЗалишкиП(м.тексти[ключ], законніТ(ключ));
  /* ПОВТОР ІЗ ТОЧНИМИ СЛОВАМИ (ПРОЗА-1). Текст, який шар уже переклав українською, але з кількома словами не кирилицею («баскa», «structурована»),
     не йде в повтор ВХІДНИМ англійським — модель переклала б усе наново, з тим самим ризиком. Такий
     ключ (переклад є, не чужою мовою, лише залишки) іде в повтор ЇЇ Ж українським текстом, а
     поруч — слова, які треба переписати (`виправ`); без відповіді чи чужою мовою — іде
     вхідним. Повтор, що з цього тексту зробив чужу мову чи порожнечу, не замінює першого
     перекладу: той лишається, і з нього знімається лише відрізок із залишком (нижче). */
  const лишеСлова = ключ => !безВідповіді.includes(ключ) && !чужоюМовоюП(м.тексти[ключ], своїТ(ключ));
  const повтор = Object.keys(т).filter(ключ => безВідповіді.includes(ключ)
                                              || чужоюМовоюП(м.тексти[ключ], своїТ(ключ))
                                              || залишкиТ(ключ).length);
  if (повтор.length){
    const виправ = Object.fromEntries(повтор.filter(лишеСлова).map(ключ => [ключ, залишкиТ(ключ)]));
    const перший = Object.assign({}, м.тексти);
    const вхідПовтору = Object.fromEntries(повтор.map(ключ => [ключ, ключ in виправ ? м.тексти[ключ] : т[ключ]]));
    /* ПОВТОР, ЩО ДОСЛІВНО ПОВТОРЮЄ ПЕРШИЙ ВИКЛИК, — ОПИС ОКРЕМО. Живий П1: на шість
       текстів картки руки 1 шар відповів формою, якої розбір не прочитав, а повтор тих самих шести
       з тим самим промптом (вибірка шару — температура 0) дав ту саму відповідь байт у байт — і
       «Чому цей образ» пішов без пояснення. Коли повтор просить усе, що просив перший виклик, і
       без `виправ`, опис іде своїм викликом, решта — своїм, паралельно: інший промпт — інша
       відповідь, а опис — головне пояснення картки — не ділить виклик ні з чим. */
    const тойСамий = повтор.length > 1 && повтор.length === Object.keys(т).length && !Object.keys(виправ).length
      && 'опис' in вхідПовтору;
    const деП = (де ? де + '.' : '') + 'retry';
    const урізаноП = урізаноПершимП(м, повтор.filter(ключ => !(ключ in виправ)));
    const м2 = тойСамий
      ? await злитиВідповідіШаруП(await Promise.all([
          мовоюП({опис: вхідПовтору.опис}, деП, undefined, речіШаруП(к, перший, вхідПовтору), undefined, урізаноП, true,
                 'Попередня відповідь пропустила, урізала або не переклала опис. Поверни його повністю.'),
          мовоюП(Object.fromEntries(Object.entries(вхідПовтору).filter(([ключ]) => ключ !== 'опис')), деП,
                 undefined, речіШаруП(к, перший, вхідПовтору), undefined, урізаноП, true,
                 'Попередня відповідь пропустила, урізала або не переклала ці рядки. Поверни кожен повністю.')]))
      : await мовоюП(вхідПовтору, деП, виправ, речіШаруП(к, перший, вхідПовтору), undefined, урізаноП, true,
                     'Попередня відповідь пропустила, урізала або не переклала ці рядки. Поверни кожен повністю.');
    /* ПОВТОР, ЩО ЗІПСУВАВ ТЕКСТ, НЕ ЗАМІНЮЄ ПЕРШОГО (ПРОЗА-КАРТОК-2): повтор мав переписати
       лише слова з `виправ`, а повернув кашу («Эос образ, який обрала для твоёго побачення сьгоди…») —
       перший переклад був чистий. Повтор, у якому з'явились нові чужі слова чи битi літери або
       якому бракує більше слів першого перекладу, ніж мало змінитись (`повторЗіпсувавП`), відкидається:
       лишається перший, а відрізок із залишком знімається з нього нижче. */
    const відхилені = Object.keys(виправ).filter(ключ => {
      return !String(м2.тексти[ключ] || '').trim() || чужоюМовоюП(м2.тексти[ключ], своїТ(ключ))
          || (м2.записи[0] && (м2.записи[0].без_відповіді || []).includes(ключ))
          || повторЗіпсувавП(перший[ключ], м2.тексти[ключ], виправ[ключ], законніТ(ключ));
    });
    if (відхилені.length) к.мова_повтор_відкинуто = [...new Set((к.мова_повтор_відкинуто || []).concat(відхилені))];
    for (const запит of м2.виклики_договору || []) запит.відхилені_тексти = відхилені;
    Object.assign(м, await злитиВідповідіШаруП([м, м2]));
    const урізано = Object.keys(м.короткі || {}).filter(ключ => повтор.includes(ключ) && !(ключ in виправ));
    if (урізано.length) к.мова_урізано = [...new Set((к.мова_урізано || []).concat(урізано))];
  }
  const н = Object.assign({}, м.тексти);
  const свідомі_ = ключ => /^свідомі\./.test(ключ);
  const лишились = Object.keys(т).filter(ключ => !свідомі_(ключ) && чужоюМовоюП(н[ключ], своїТ(ключ)));
  /* опис і назва лишаються в картці як є — їх читають звіт і приміряння; не малює їх `рендерКартку` */
  лишились.forEach(ключ => { if (ключ !== 'опис' && !/\.назва$/.test(ключ)) н[ключ] = ''; });
  /* ЗАЙВА ЛАТИНКА, що лишилась і після повтору (ВМ-3в): відрізок з нею знімається, решта тексту
     йде жінці; назва речі з нею не малюється (як чужа). Що знято — у `латиниця_знята`. */
  const знята = {};
  Object.keys(т).forEach(ключ => {
    if (свідомі_(ключ) || лишились.includes(ключ)) return;
    const вона = латинськіЗалишкиП(н[ключ], законніТ(ключ));
    if (!вона.length) return;
    знята[ключ] = вона;
    if (/\.назва$/.test(ключ)){
      /* Назва «Перлова підвіска з ланцюжком із золота 18k» не лягала на картку вся через «18k» і лишала
         рядок порожнім; тепер знімаються лише чужі слова, а назва, що без них ще читається, йде жінці. */
      const назва = назваБезЛатинкиП(н[ключ], законніТ(ключ));
      if (назва) н[ключ] = назва; else лишились.push(ключ);
      return; }
    н[ключ] = безЗайвоїЛатинкиП(н[ключ], законніТ(ключ));
    if (ключ === 'опис' && !н[ключ]) лишились.push(ключ);
  });
  if (Object.keys(знята).length) к.латиниця_знята = Object.assign(к.латиниця_знята || {}, знята);
  if (к.свідомі && к.свідомі.length)
    к.свідомі = к.свідомі.map((х, і) => {
      const ключ = 'свідомі.' + і, т_ = н[ключ];
      return (ключ in т) && т_ && т_ !== НАПИС_БЕЗ_ТЕКСТУ_П
        && т_ !== НАПИС_БЕЗ_ШАРУ_П.card_without_description
        && станТекстуЖінціП(т_, законніТ(ключ)) === 'translated'
        ? т_ : шаблонХодуКарткиП(к, і); });
  /* Ч-7: маршрут повідомлень уже міг щось сюди дописати — не затирати його */
  if (лишились.length) к.мова_не_перекладено = [...new Set((к.мова_не_перекладено || []).concat(лишились))];
  ПОЛЯ_КАРТКИ_ЖІНЦІ.forEach(п => { if (п in т) к[п] = н[п]; });
  /* абзаци про речі (ПЕРЕКЛАД-36) — назад в один опис, у тому самому порядку; абзац, що лишився чужою мовою, випадає,
     як рядок «Як це носити» */
  const описК = описи ? [...Object.keys(описи.тексти).map(ключ => н[ключ]), описи.решта ? н['опис'] : '']
                          .filter(х => String(х || '').trim()).join('\n')
                      : н['опис'];
  /* ОРИГІНАЛ «ЯК НОСИТИ» ЛИШАЄТЬСЯ ПОРУЧ ІЗ ПЕРЕКЛАДОМ (п.12): примірка кладе ці рядки в
     англійський промпт картинки (`how_to_wear`), а переклад їй — українська фраза в англійському
     промпті. Перший переклад картки зберігає оригінал, повторний його не затирає; заміна речі скидає
     його разом з описом (`замінитиРічП`). */
  if (задум.length && !к.як_носити_оригінал) к.як_носити_оригінал = задум.slice();
  if (опис || задум.length){ к.опис = опис ? описК : к.опис; к.як_носити = задум.map((р, і) => н['як_носити.' + і]); }
  (к.речі || []).forEach((x, і) => ПОЛЯ_РЕЧІ_ЖІНЦІ.concat(['назва']).forEach(п => {
    if (('річ.' + і + '.' + п) in т) x[п] = н['річ.' + і + '.' + п]; }));
  к.мова_шару = (к.мова_шару || []).concat(м.записи);
}
/* Називає предмет відхиленого ходу за ID, не читаючи слів відхиленої відповіді. */
function шаблонХодуКарткиП(к, номер){
  const ід = new Set((к.свідомі_ід || [])[номер] || []);
  const свої = законніКарткиП(назвиКаталогуКарткиП(к));
  const назви = (к.речі || []).filter(р => р && ід.has(р.id) && typeof р.назва === 'string'
    && станНазвиЖінціП(р.назва) === 'translated'
    && станТекстуЖінціП(р.назва, свої) === 'translated').map(р => р.назва);
  return (назви.length ? назви.join(', ') + ' — ' : '') + НАПИС_БЕЗ_ШАРУ_П.card_without_description;
}
/* Питання card_unchecked перекладаються окремими пачками повідомлень.
   Збій пачки не забирає опису й решти питань; шаблон не видається за переклад
   і не потрапляє до пам’яті прийнятих відповідей. */
const ПИТАНЬ_НА_ВИКЛИК_П = 15;
const ПАМ_ЯТЬ_ПИТАНЬ_П = new Map();
const СТЕЛЯ_ПАМ_ЯТІ_ПИТАНЬ_П = 600;
/* На картці лишаються питання саме цього образу.
   Пам’ять зберігає переклад заяви за її ключем, тому перемальовування
   не кличе модель удруге для того самого питання. */
const ЧЕКАЮТЬ_ПИТАННЯ_П = new Map();
const КНОПКА_ПИТАНЬ_П = {kind: 'card_unknowns_toggle', statements: [{code: 'unchecked_in_this_look'}]};
const КЛЮЧ_КНОПКИ_ПИТАНЬ_П = JSON.stringify(КНОПКА_ПИТАНЬ_П);
/* ── ПИТАННЯ КОЛЬОРУ ПРО РЕЧІ ЦЬОГО ОБРАЗУ — ЗА КНОПКОЮ, РЕЧЕННЯ ПІСЛЯ ДОТИКУ (п.9) ──────
   Міст позначає їх `на_розгортання` (K-COL-06 «два різні білі» й «дві нейтралі», K-COL-01): вони
   про речі саме цього образу, тож на картці їм місце, але шар під час збирання їх не пише — збирання не
   чекає на них жодного виклику. Підпис кнопки лічить і їх; речення шар пише тоді, коли жінка розгорне
   кнопку (`розгорнуто` — виклик із картки, `дописатиРозгорнутіП`), тією самою пам'яттю й пачками. */
function чекаютьРозгортанняП(к){
  if (!МОДЕЛЬ_МОВИ_П) return 0;
  return new Set(((к && к.питання) || []).filter(п => п && п.на_розгортання && !п.для_всіх && !п.текст
    && п.повідомлення && п.повідомлення.kind).map(п => JSON.stringify(п.повідомлення))).size;
}
async function питаннямиП(к, де, розгорнуто){
  const усі = (к && к.питання) || [];
  const ключ = п => (п && п.повідомлення && п.повідомлення.kind && !п.для_всіх) ? JSON.stringify(п.повідомлення) : null;
  const тепер = п => ключ(п) && (розгорнуто ? п.на_розгортання && !п.текст : !п.на_розгортання);
  if (!МОДЕЛЬ_МОВИ_П || !усі.some(ключ)) return;
  /* [ключ пам'яті, ключ у виклику, повідомлення] — кожне питання раз, напис розкривача останнім */
  const елементи = [], бачені = new Set();
  усі.forEach((п, і) => { const к_ = тепер(п) && ключ(п);
    if (к_ && !бачені.has(к_)){ бачені.add(к_); елементи.push([к_, 'питання.' + і, п.повідомлення]); } });
  /* Напис приєднується до перекладу нових питань; сам по собі збирання не затримує. */
  if (!розгорнуто && елементи.some(([к_]) => !ПАМ_ЯТЬ_ПИТАНЬ_П.has(к_) && !ЧЕКАЮТЬ_ПИТАННЯ_П.has(к_)))
    елементи.push([КЛЮЧ_КНОПКИ_ПИТАНЬ_П, 'кнопка', КНОПКА_ПИТАНЬ_П]);
  const нема = елементи.filter(([к_]) => !ПАМ_ЯТЬ_ПИТАНЬ_П.has(к_));
  const нові = нема.filter(([к_]) => !ЧЕКАЮТЬ_ПИТАННЯ_П.has(к_));
  const чужі = [...new Set(нема.filter(([к_]) => ЧЕКАЮТЬ_ПИТАННЯ_П.has(к_)).map(([к_]) => ЧЕКАЮТЬ_ПИТАННЯ_П.get(к_)))];
  const своя = нові.length ? питатиПачкамиП(нові, де) : Promise.resolve({записи: [], стани: new Map()});
  нові.forEach(([к_]) => ЧЕКАЮТЬ_ПИТАННЯ_П.set(к_, своя));
  let результат;
  try { результат = await своя; }
  finally { нові.forEach(([к_]) => { if (ЧЕКАЮТЬ_ПИТАННЯ_П.get(к_) === своя) ЧЕКАЮТЬ_ПИТАННЯ_П.delete(к_); }); }
  const спільні = await Promise.allSettled(чужі);
  const стани = new Map(результат.стани);
  for (const р of спільні) if (р.status === 'fulfilled')
    for (const [к_, стан] of р.value.стани) стани.set(к_, стан);
  к.питання = усі.map(п => {
    if (!тепер(п)) return {...п};
    const к_ = ключ(п), зПамяті = ПАМ_ЯТЬ_ПИТАНЬ_П.get(к_);
    const стан = зПамяті ? {текст: зПамяті, стан: 'translated'} : стани.get(к_)
      || {текст: НАПИС_БЕЗ_ШАРУ_П.card_unchecked, стан: 'fallback'};
    return {...п, текст: стан.текст, стан_перекладу: стан.стан};
  });
  к.питання_жінці = к.питання.filter(ключ).map(п => п.текст).filter(Boolean);
  к.питання_кнопка = ПАМ_ЯТЬ_ПИТАНЬ_П.get(КЛЮЧ_КНОПКИ_ПИТАНЬ_П) || null;
  /* СКІЛЬКИ ПИТАНЬ ЦІЄЇ КАРТКИ ШАР НЕ ПИТАВ ДРУГИЙ РАЗ (ГТ-1): те саме питання (ті самі
     коди) пам'ятається на весь показ, тож картка, що збирається ПІСЛЯ сусідньої, дістає частину
     речень з пам'яті, і її власні записи шару лічать лише решту. Речення на картці є — але журнал без цього числа не міг це
     показати, і лічба «питань → відповідей» розходилась би залежно від того, яка рука встигла першою.
     Число (внутрішня мова) лягає в картку, звідти у звіт. Сюди ж — питання, які картка
     дочекалась із виклику сусідньої (`ЧЕКАЮТЬ_ПИТАННЯ_П`); напис розкривача не лічиться. */
  const зіСпільного = к.питання.filter((п, і) => тепер(усі[і]) && п.стан_перекладу === 'translated').length
    - нові.filter(([к_, кв]) => кв !== 'кнопка' && результат.стани.get(к_)?.стан === 'translated').length;
  к.питання_з_пам_яті = (розгорнуто ? к.питання_з_пам_яті || 0 : 0) + зіСпільного;
  if (результат.записи.length) к.мова_шару = (к.мова_шару || []).concat(результат.записи);
}
