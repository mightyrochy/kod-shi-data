const ЖУРНАЛ_ЗБОЇВ_ЖІНЦІ_П = [];
const СТАНИ_НЕ_МОВИ_П = ['foreign_language', 'latin_remainder', 'service_code', 'polite_form'];
function станТекстуЖінціП(т, свої){
  return typeof т !== 'string' || !т.trim() ? 'missing_text'
    : чужоюМовоюП(т, свої) ? 'foreign_language'
    : латинськіЗалишкиП(т, свої).length ? 'latin_remainder'
    : СЛУЖБОВИЙ_КОД_П.test(т) ? 'service_code'
    : ЗВЕРТАННЯ_ВИ_П.test(т) ? 'polite_form' : 'translated';
}
/* «Ти» — рішення власника; «ви» у тексті ходу — вада мови, її ловить сторож, а не лише промпт (6074, ПС-21): слова — у повтор
   шару (`виправ`), що лишилось після повтору, знімається відрізком-реченням, як латинка. */
function звертанняВиП(т){
  const р = new RegExp(ЗВЕРТАННЯ_ВИ_П.source, 'giu');
  return [...String(т || '').matchAll(р)].map(м => м[0]);
}
function безЗвертанняВиП(т){
  return String(т || '').split('\n').map(рядок => рядок.split(/(?<=[.!?…])\s+/)
    .filter(речення => !ЗВЕРТАННЯ_ВИ_П.test(речення)).join(' ')).filter(рядок => рядок.trim()).join('\n');
}
/* Запис у поле екрана: textContent (типово), placeholder/title/alt чи aria-label. Єдине місце, де код пише текст жінці. */
function полеЕкранаП(елемент, поле, значення){
  if (!елемент) return;
  if (поле === 'aria-label') елемент.setAttribute(поле, значення);
  else елемент[поле || 'textContent'] = значення;
}
function збійЖінціП(елемент, вид, причина, поле){
  const шаблон = ШАБЛОНИ_ЗБОЮ_П[вид] || ШАБЛОНИ_ЗБОЮ_П.without_text;
  ЖУРНАЛ_ЗБОЇВ_ЖІНЦІ_П.push({вид, причина: String((причина && причина.message) || причина || '').slice(0, 300)});
  if (ЖУРНАЛ_ЗБОЇВ_ЖІНЦІ_П.length > 100) ЖУРНАЛ_ЗБОЇВ_ЖІНЦІ_П.shift();
  полеЕкранаП(елемент, поле, шаблон);
  return шаблон;
}
