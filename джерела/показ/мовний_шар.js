const СЛУЖБОВИЙ_КОД_П = /(?<![\p{L}\p{N}])[a-z][a-z0-9]*(?:_[a-z0-9]+)+(?![\p{L}\p{N}])|(?<![\p{L}\p{N}])ж-\d{3,}/u;
