/* ── МОВНИЙ ШАР: ОДНА ТОЧКА НА ВИХОДІ ДО ІНТЕРФЕЙСУ (рішення власника) ──
   «Модель, спеціаліст з української мови, просто робить весь текст, що бачить
   людина, природним. Вона сама не приймає жодних рішень, не відповідає на питання,
   не обробляє інформацію і не збирає образи. Це перекладач.»
   ДЕ СТОЇТЬ. Кожен текст, який функціональні моделі й код складають для жінки,
   проходить `мовоюП` рівно там, де зміст уже готовий, а на екран ще не ліг: репліка
   стилістки в чаті (`слатиЧатП`), тексти картки (`мовоюКарткуП` наприкінці руки) і
   підпис приміряння (`приміряти`). Сталі написи інтерфейсу (кнопки, заголовки,
   підказки полів) сюди не йдуть: їх не складає жодна модель, вони — сама сторінка.
   ЩО РОБИТЬ КОД, А ЩО МОДЕЛЬ. Python (`мовний_шар`, ендпойнт `мова`) будує промпт і
   читає відповідь; мову пише модель, і змісту її код не судить: «Всі інші костилі не
   потрібні» (власник, 25.09). Точність видно у звіті власника — на кожен виклик шару
   один запис: напрям, де, модель, коли, скільки мс, вхід і вихід повністю.
   НІКОЛИ НЕ КИДАЄ: збій моста чи моделі — вхідні тексти й запис із причиною. Шар не
   має права зупинити жінці розмову чи образи. Без моделі шару (`МОДЕЛЬ_МОВИ_П ===
   null`) — вхідні тексти без жодного виклику, як до 25.09. */
/* `вибірка` — з відповіді ендпойнта `мова` поруч із промптом (М-2: температура 0 — та сама
   репліка дає той самий переклад, а отже й той самий паспорт) */
/* `запис` — запис виклику шару для звіту: його `модель` — лише мітка сторінки (хеш посилання
   або типова), а хто відповів насправді, каже заголовок `x-model` ЦЬОГО виклику (`заголовкиВих`, не
   «останній» глобальний — виклики шару ідуть упереміж). Заголовка нема — лишається мітка сторінки. */
async function модельМовиП(промпт, вибірка, запис, сигнал){
  const заголовки = {};
  const текст = блокиВТекст(await модельП_блоки([{type:'text', text:String(промпт || '')}], МОДЕЛЬ_МОВИ_П,
                                                undefined, заголовки, undefined, undefined, вибірка, сигнал));
  if (запис && заголовки['x-model']) запис.модель = заголовки['x-model'];
  return текст;
}
/* ── ПРИЧИНИ ЗБОЮ ШАРУ — КОДАМИ, НЕ ФРАЗАМИ (М-3, аудит/ПРОДУКТ.md п.12) ──────────────
   Доти `причина` записів шару була українським реченням, яке складав САМ КОД («шар не
   спрацював: міст не дав промпта»), і воно їхало у звіт власника. Тепер це коди
   внутрішньої мови, які не ламаються від зміни локалізації:
     · `bridge_no_prompt`      — ендпойнт `мова` не дав промпта;
     · `bridge_no_answer`      — ендпойнт `мова` не прочитав відповідь моделі;
     · `no_language_model`     — моделі шару в показі нема (запасної фрази не буває);
     · `passport_not_assembled`— шов не склав паспорта з перекладу;
     · `layer_failed: <текст>` — виняток на шляху; після двокрапки — сире повідомлення
       рантайму (не текст коду), за цим префіксом відмову шару впізнає `розмоваЯкMainП`.
   Речення жінці з цього не пишеться ніколи: нема тексту шару — нема рядка (як доти). */
/* `виправ` — {ключ: [слова]} (ПРОЗА-1): текст ключа вже переклала модель шару, і в ньому лише ці
   слова не кирилицею; їх промпт називає поруч із текстом (`мовний_шар.розмітити`).
   `речі` — речі картки для перекладачки (ПЕРЕКЛАД-34, `речіШаруП`): промпт називає кожну номером із назвою,
   і вид речі в перекладі — іменник цієї назви (`мовний_шар._абзац_речей`).
   `урізано` — {ключ: код}: перший переклад ключа урізано (`мовний_шар._урізано`), і повтор
   несе причину в промпт, а не той самий промпт удруге; відповідь кладе свої урізані ключі в `вих.урізано`. */
async function мовоюП(тексти, де, виправ, речі, сигнал, урізано, зовнішній_повтор=false, розбіжність=''){
  const вих = {тексти: Object.assign({}, тексти || {}), записи: [], виклики_договору: []};
  const є = Object.keys(вих.тексти).filter(к => /\p{L}/u.test(String(вих.тексти[к] || '')));
  if (!МОДЕЛЬ_МОВИ_П || !є.length) return вих;
  const запис = {напрям: 'out', де: де || '', модель: МОДЕЛЬ_МОВИ_П, коли: new Date().toISOString(),
                 вхід: Object.fromEntries(є.map(к => [к, String(вих.тексти[к])]))};
  if (виправ && Object.keys(виправ).length) запис.виправ = виправ;
  if (урізано && Object.keys(урізано).length) запис.урізано_першим = урізано;
  if ((речі || []).length) запис.речі = речі;
  const почато = Date.now();
  try{
    const р1 = await містП('мова', Object.assign({тексти: запис.вхід},
                                                  розбіжність ? {помилка_формату: розбіжність} : {},
                                                  запис.виправ ? {виправ: запис.виправ} : {},
                                                  запис.урізано_першим ? {урізано: запис.урізано_першим} : {},
                                                  запис.речі ? {речі: запис.речі} : {}));
    if (!р1 || р1.помилка) throw new Error((р1 && р1.помилка) || 'bridge_no_prompt');
    if (р1.промпт){
      if (р1.вибірка) запис.вибірка = р1.вибірка;
      const відповідь = await модельМовиП(р1.промпт, р1.вибірка, запис, сигнал);
      const запит = {розмітка: р1.розмітка, відповідь_моделі: відповідь};
      вих.виклики_договору.push(запит);
      const р2 = await містП('мова', запит);
      if (!р2 || р2.помилка || !р2.тексти) throw new Error((р2 && р2.помилка) || 'bridge_no_answer');
      Object.assign(вих.тексти, р2.тексти);
      /* урізаний переклад (ОПИС-1, `мовний_шар._урізано`): ключ стоїть у
         `без_відповіді`, а сам переклад — тут, щоб повтор міг віддати довший із двох */
      if (р2.короткі && Object.keys(р2.короткі).length){ вих.короткі = р2.короткі; запис.короткі = р2.короткі; }
      if (р2.урізано && Object.keys(р2.урізано).length){ вих.урізано = р2.урізано; запис.урізано = р2.урізано; }
      if ((р2.без_відповіді || []).length)
        Object.assign(запис, {без_відповіді: р2.без_відповіді, причина: р2.причина, відповідь_моделі: відповідь});
      /* форму відповіді, яку розбір дочитав (збитий екран, текст у полі вхідної форми — П-3),
         запис називає, а сиру відповідь тримає поруч: мовчки не лагодиться нічого */
      if ((р2.нотатки || []).length) Object.assign(запис, {нотатки: р2.нотатки, відповідь_моделі: відповідь});
    }
  }catch(e){
    Object.assign(запис, {без_відповіді: є, причина: 'layer_failed: ' + String((e && e.message) || e)});
  }
  запис.мс = Date.now() - почато;
  запис.вихід = Object.fromEntries(є.map(к => [к, вих.тексти[к]]));
  вих.записи = [запис];
  const відсутні = запис.без_відповіді || [];
  if (!зовнішній_повтор && відсутні.length && !/^layer_failed:/.test(запис.причина || '')
      && !(сигнал && сигнал.aborted)){
    const ще = await мовоюП(Object.fromEntries(відсутні.map(к => [к, вих.тексти[к]])),
      (де || '') + '.retry', виправ, речі, сигнал, вих.урізано, true,
      'Відповідь не містить повного тексту для ключів: ' + відсутні.join(', ') + '. Поверни кожен із цих рядків.');
    Object.assign(вих, await злитиВідповідіШаруП([вих, ще]));
  }
  return вих;
}
/* ── УРІЗАНЕ Й ПІСЛЯ ПОВТОРУ (ОПИС-1) ─────────────────────────────────
   Шар, що урізав прозу (переклад коротший за 60 % джерела або обірваний «...»), повтором
   лагодиться не завжди: повтор може повернути той самий урізаний опис. Тоді
   на картку йде ДОВШИЙ із двох урізаних перекладів, а не англійське джерело, — і ключ
   стоїть у `мова_урізано` картки (звіт). Ключі, які повтор переклав повністю, не чіпає. */
/* причина першого урізання тих ключів, що йдуть у повтор: {ключ: код}, порожнє — без урізаних */
function урізаноПершимП(м, ключі){
  return Object.fromEntries((ключі || []).filter(ключ => ((м || {}).урізано || {})[ключ]).map(ключ => [ключ, м.урізано[ключ]]));
}
/* Кілька відповідей `мовоюП` (повтор, поділений на виклики) → одна тієї ж форми. */
async function злитиВідповідіШаруП(відповіді){
  const виклики = (відповіді || []).flatMap(в => в.виклики_договору || []);
  const записи = відповіді.flatMap(в => в.записи || []);
  try{
    const р = await містП('мова', {відповіді_шару: виклики});
    if (!р || р.помилка) throw new Error((р && р.помилка) || 'bridge_no_answer');
    return перевіритиКінцевуВідповідьШаруП(Object.assign({}, р, {записи, виклики_договору: виклики}));
  }catch(e){
    // Без відповіді судді нових даних немає; вже прийнятий результат залишається доступним.
    записи.push({напрям: 'out', де: 'merge', коли: new Date().toISOString(),
      причина: 'layer_failed: ' + String((e && e.message) || e)});
    return перевіритиКінцевуВідповідьШаруП(Object.assign({}, відповіді[0], {записи, виклики_договору: виклики}));
  }
}
/* Схема межі вже прочитала кінцевий об'єкт; сторож мови стоїть перед його показом і кешем.
   Цю саму перевірку використовуємо до повтору, щоб пояснити моделі відхилення. */
function перевіритиКінцевуВідповідьШаруП(результат){
  const р = {...результат, тексти: {...результат.тексти}};
  const без = new Set(р.заяви ? [] : (р.без_відповіді || []));
  const станТексту = станТекстуЖінціП;
  if (р.заяви){
    р.заяви = р.заяви.map(з => {
      const свої = своїСловаП({одна: {statements: з.заяви}});
      const стан = станТексту(з.текст, свої);
      if (стан !== 'translated'){
        без.add(з.ключ);
        delete р.тексти[з.ключ];
      }
      return {...з, стан};
    });
    р.чужою = [...new Set(р.заяви.filter(з => СТАНИ_НЕ_МОВИ_П.includes(з.стан))
      .map(з => з.повідомлення))];
  }else{
    const входи = Object.assign({}, ...(р.виклики_договору || []).map(з =>
      Object.fromEntries((з.розмітка || []).map(в => [в.ключ, в.текст]))));
    for (const [ключ, т] of Object.entries(р.тексти)){
      if ((без.has(ключ) && !(р.короткі || {})[ключ])
          || станТексту(т, своїВходуП(входи[ключ] || '')) !== 'translated'){
        без.add(ключ);
        р.тексти[ключ] = НАПИС_БЕЗ_ТЕКСТУ_П;
      }
    }
  }
  р.без_відповіді = [...без];
  return р;
}
