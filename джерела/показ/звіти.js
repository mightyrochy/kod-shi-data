/* ПРАВИЛО ЗБИРАННЯ — ОДНЕ Й ОГОЛОШЕНЕ ТУТ. Звіт розбирає не показ,
   а сесія-діагност; але правило «поля вердикта = спільне файла + спільне
   прогону + сам вердикт, і те саме всередині `етапи`» мусить мати ОДНЕ місце,
   інакше кожен читач (батарея, стенд, проба, майбутня сесія) напише своє, і
   вони розійдуться рівно так, як розходяться два списки плейсхолдерів. Рядок
   `як_читати` у файлі переказує це людськими словами, ця функція — кодом. */
function злитиВердикт(звіт, прогін, вердикт){
  const сф = (звіт || {}).спільне || {}, сп = (прогін || {}).спільне || {};
  const о = {...сф, ...сп, ...(вердикт || {})};
  const ет = {...(сф.етапи || {}), ...(сп.етапи || {}), ...((вердикт || {}).етапи || {})};
  if (Object.keys(ет).length) о.етапи = ет; else delete о.етапи;
  return о;
}
/* ── ОДИН ВЕРДИКТ — ОДИН РЯДОК ФАЙЛА ────────────────────────────
   `JSON.stringify(звіт, null, 1)` читається очима найкраще і коштує найдорожче:
   виміряно пробою `проби/звіт_вердиктів_134.js` — 20 вердиктів це 76.7 КБ проти
   48.3 КБ тим самим вмістом, тобто +59 % контексту за самі пробіли. Голий
   `JSON.stringify` дешевий, але кладе весь звіт в ОДИН рядок, у якому не
   покажеш пальцем на руку.
   Тому відступ стоїть рівно там, де він щось РОЗРІЗНЯЄ: шапка файла —
   рядок на поле, шапка прогону — рядок на поле, а вердикт — один рядок на
   вердикт (те саме зерно, що JSONL, тільки всередині самоописового контейнера).
   Коштує це ~1 %, а не 60 %. Збирається зі шматків, кожен з яких зробив
   `JSON.stringify`, — тож екранування лишається штатним, і переноси в довгому
   тексті не чавляться (саме за цим файл і затівався). */
function обʼєктРядками(о, відступ){
  const кл = Object.keys(о || {});
  if (!кл.length) return '{}';
  return '{\n' + кл.map(к => відступ + ' ' + JSON.stringify(к) + ': ' + JSON.stringify(о[к])).join(',\n')
       + '\n' + відступ + '}';
}
function звітТекстом(з){
  const частини = Object.keys(з)
    .filter(к => к !== 'прогони' && к !== 'спільне')
    .map(к => ' ' + JSON.stringify(к) + ': ' + JSON.stringify(з[к]));
  частини.push(' "спільне": ' + обʼєктРядками(з.спільне, ' '));
  частини.push(' "прогони": [\n' + (з.прогони || []).map(п =>
      '  {"прогін": ' + JSON.stringify(п.прогін) + ', "вердиктів": ' + JSON.stringify(п.вердиктів)
      + ',\n   "спільне": ' + обʼєктРядками(п.спільне, '   ')
      + ',\n   "вердикти": [\n'
      + (п.вердикти || []).map(в => '    ' + JSON.stringify(в)).join(',\n')
      + ']}').join(',\n') + ']');
  return '{\n' + частини.join(',\n') + '\n}\n';
}
