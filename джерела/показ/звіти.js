/* ── СПИСОК ВИБОРУ: ДЕНЬ → ПРОГІН → ОБРАЗ ───────────────────────────────────
   Три рівні, бо власник просив рівно три ці зерна («які прогони/дні/образи»).
   Позначка на дні чи прогоні — це та сама позначка на їхніх образах: окремого
   стану в групи нема, тож список не може розійтися сам із собою. */
let ВИБІР_ВИВАНТАЖЕННЯ_П = [];
function рядокВивантаженьП(з){
  const в = (з || {}).вивантажено || [];
  return в.length ? ('вже вивантажено ' + в.length + '\u00d7, останнє '
                     + String(в[в.length-1]).slice(0,16).replace('T',' '))
                  : 'ще не вивантажено';
}
function згодаГрупиП(гр){
  гр.вх.checked = гр.діти.length ? гр.діти.every(д => д.вх.checked) : false;
  гр.вх.indeterminate = !гр.вх.checked && гр.діти.some(д => д.вх.checked);
}
async function малюватиВибірВивантаженняП(){
  const м = $('жв-список'); if (!м) return;
  /* ЧИТАННЯ — ДО ОЧИЩЕННЯ, І ВСЯ ЗБІРКА ПІСЛЯ НЬОГО СИНХРОННА. Скидання масиву
     перед `await` дало б перегони двох малювань (кнопка «зберегти позначене»
     перемальовує список сама, і клік по ній лягає на вже початкове малювання):
     обидві збірки пушили б у той самий масив, і вибір рахувався б на подвоєному
     переліку. Тепер останній виклик просто заміщає попередній цілком. */
  let усі = [];
  try{ усі = await усіВердиктиЗКлючами(); }
  catch(e){ ВИБІР_ВИВАНТАЖЕННЯ_П = []; м.innerHTML = '';
            збійЖінціП(м, 'journal_unreadable', e); return; }
  ВИБІР_ВИВАНТАЖЕННЯ_П = [];
  м.innerHTML = '';
  /* Порожній журнал теж мусить оновити кнопку: активна «Зберегти позначене» над
     порожнім списком обіцяє дію, якої нема. */
  if (!усі.length){ м.textContent = 'Поки нема чого вибирати: запиши бодай один вердикт.';
                    оновитиЛічбуВиборуП(); return; }
  усі.sort((а, б) => String(б.зап.час || '').localeCompare(String(а.зап.час || '')));
  const дні = new Map();
  for (const р of усі){
    const д = String(р.зап.дата || String(р.зап.час || '').slice(0,10) || 'без дати');
    if (!дні.has(д)) дні.set(д, new Map());
    const пр = КЛЮЧ_ПРОГОНУ(р.зап);
    const пм = дні.get(д);
    if (!пм.has(пр)) пм.set(пр, []);
    пм.get(пр).push(р);
  }
  const птах = (текст, клас) => {
    const л = ел('label', клас);
    const вх = document.createElement('input'); вх.type = 'checkbox';
    л.appendChild(вх); л.appendChild(елЖінціП('span', null, текст));
    return {л: л, вх: вх};
  };
  for (const [день, прогони] of дні){
    const гд = ел('div', 'жв-день');
    const лічбаД = [...прогони.values()].reduce((а, сп) => а + сп.length, 0);
    const шд = птах(день + ' · прогонів ' + прогони.size + ' · вердиктів ' + лічбаД, 'жв-шапка');
    гд.appendChild(шд.л);
    const дітиД = [];
    for (const [прогін, список] of прогони){
      const гп = ел('div', 'жв-прогін');
      /* ЗАГОЛОВОК ПРОГОНУ — ТЕ, ЧИМ ВЛАСНИК ЙОГО ВПІЗНАЄ: година й розклад рук.
         Сам ключ (`збірка·розклад·профіль`) несе підпис збірки на півтора рядки —
         на телефоні це смуга тексту, у якій прогони на вигляд однакові. Підпис
         збірки нікуди не зникає: він стоїть у шапці прогону в самому файлі. */
      /* ГОДИНА З СЕКУНДАМИ (наряд Л-7): доти два збори з тією самою перестановкою
         рук були ОДНІЄЮ групою (той самий ключ), тож і питання не стояло. Тепер це
         два прогони — і два рядки «прогін о 20:12 · розклад 3142» під палець
         власника були б нерозрізненні, якби він зібрав образи двічі за одну
         хвилину. Секунди тут — не окраса: ними він вибирає, що вивантажити. */
      const пч = String((список[список.length-1].зап.час) || '').slice(11,19);
      /* Номер руки (і розклад — він же, рука за рукою) видно, лише коли прогін оцінено ЦІЛКОМ —
         записів стільки, скільки карток у розкладі; впала рука теж записується, тож чекати нема на що. */
      const карток = String(список[0].зап.розклад ?? '').length;
      const оцінено = !карток || new Set(список.map(р => р.зап.позиція)).size >= карток;
      const шп = птах('прогін' + (пч ? ' о ' + пч : '')
                      + (оцінено ? ' · розклад ' + (список[0].зап.розклад ?? '?') : '')
                      + ' · вердиктів ' + список.length, 'жв-шапка жв-друга');
      гп.appendChild(шп.л);
      const дітиП = [];
      for (const р of список){
        const номер = (ЧИСЛА[(+р.зап.позиція || 1) - 1] || р.зап.позиція);
        const верд = р.зап.рука_впала ? 'рука впала' : (р.зап.вердикт_людини || 'без вердикта');
        const рука = (оцінено || !/^[1-4]$/.test(String(р.зап.рука))) ? ' · рука ' + (р.зап.рука || '?') : '';
        const рб = птах(номер + ' образ' + рука + ' · ' + верд
                        + ' · ' + рядокВивантаженьП(р.зап), 'жв-образ');
        const вузол = {вх: рб.вх, ключ: р.ключ, зап: р.зап,
                       вивантажений: !!((р.зап.вивантажено || []).length)};
        ВИБІР_ВИВАНТАЖЕННЯ_П.push(вузол);
        дітиП.push(вузол); дітиД.push(вузол);
        рб.вх.onchange = ()=>{ згодаГрупиП({вх: шп.вх, діти: дітиП});
                               згодаГрупиП({вх: шд.вх, діти: дітиД}); оновитиЛічбуВиборуП(); };
        гп.appendChild(рб.л);
      }
      шп.вх.onchange = ()=>{ дітиП.forEach(д => { д.вх.checked = шп.вх.checked; });
                             шп.вх.indeterminate = false;
                             згодаГрупиП({вх: шд.вх, діти: дітиД}); оновитиЛічбуВиборуП(); };
      гд.appendChild(гп);
    }
    шд.вх.onchange = ()=>{ дітиД.forEach(д => { д.вх.checked = шд.вх.checked; });
                           шд.вх.indeterminate = false;
                           гд.querySelectorAll('.жв-друга input').forEach(в => {
                             в.checked = шд.вх.checked; в.indeterminate = false; });
                           оновитиЛічбуВиборуП(); };
    м.appendChild(гд);
  }
  позначитиВибірП(в => !в.вивантажений);   /* типово — те, чого власник ще не бачив */
}
function позначитиВибірП(предикат){
  ВИБІР_ВИВАНТАЖЕННЯ_П.forEach(в => { в.вх.checked = !!предикат(в); });
  const м = $('жв-список');
  if (м) м.querySelectorAll('.жв-шапка input').forEach(вх => {
    const гр = вх.closest('.жв-день, .жв-прогін');
    const діти = [...гр.querySelectorAll('.жв-образ input')];
    вх.checked = діти.length ? діти.every(д => д.checked) : false;
    вх.indeterminate = !вх.checked && діти.some(д => д.checked);
  });
  оновитиЛічбуВиборуП();
}
