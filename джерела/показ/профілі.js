  const y_Пл = y(.19), y_Гр = y(.29), y_Тл = y(.415), y_Ст = y(.555), y_Зр = y(.88);
  const шПл = пів(пл), шГр = пів(гр), шТл = пів(тл), шСт = пів(ст);
