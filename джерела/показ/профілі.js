/* СТАРІ ЗАПИСИ (рішення 31.10, 11781): до виправлення код сам писав у назву свій сталий напис — профілю «мій профіль»
   і «профіль N» (`'профіль ' + (ПРОФІЛІ.length + 1)`), сценарію «Сценарій <дата>» (`типоваНазваСценарію`,
   `toLocaleDateString('uk-UA')`); інших писачів напису в історії нема. Читач очищає рівно ці значення один раз — до
   позначки `назви-очищено` у сховищі: далі в назві лише її ввід, і її «мій профіль» лишається її словами. Назву
   сценарію з нагоди чи паспорта старий код теж писав, але це не сталий напис, і її слова за схожістю не впізнаємо. */
const СТАРІ_НАПИСИ_П = {профіль: /^(мій профіль|профіль [1-9][0-9]*)$/, сценарій: /^Сценарій [0-9]{2}\.[0-9]{2}\.[0-9]{4}$/};
async function очиститиСтаріНазвиП(){
  if (await читатиКв_('назви-очищено')) return;
  const старий = (вид, з)=>!!з && typeof з.назва === 'string' && СТАРІ_НАПИСИ_П[вид].test(з.назва);
  if (ПРОФІЛІ.some(п=>старий('профіль', п))){
    ПРОФІЛІ.forEach(п=>{ if (старий('профіль', п)) п.назва = ''; });
    await писатиКв('профілі', ПРОФІЛІ);
  }
  for (const ід of ПРОФІЛІ.map(п=>п && п.ід).concat(['без'])){
    const ч = await читатиКв_('випадок:' + ід);
    if (ч && старий('сценарій', ч.сц)){ ч.сц.назва = ''; await писатиКв('випадок:' + ід, ч); }
  }
  const d = await дб();
  await tx(d, 'сценарії', 'readwrite', s=>{ const к = s.openCursor();
    к.onsuccess = ()=>{ const c = к.result; if (!c) return;
      if (старий('сценарій', c.value)) c.update(Object.assign({}, c.value, {назва: ''}));
      c.continue(); }; });
  await писатиКв('назви-очищено', true);
}

async function завантажитиПрофілі(){
  ПРОФІЛІ = (await читатиКв_('профілі')) || [];
  АКТИВНИЙ = (await читатиКв_('активний')) || null;
  try{ await очиститиСтаріНазвиП(); }catch(e){}
  /* перенос старих даних: до профілів кольори, драпіровка й фото лежали під
     сталими ключами — це чиєсь уже зроблене фото, викидати не можна */
  if (!ПРОФІЛІ.length){
    const старий_к = await читатиКв_('колір'), старий_д = await читатиКв_('драп');
    const ід = новийІд();
    ПРОФІЛІ = [{ід, назва: ''}];
    АКТИВНИЙ = ід;
    await писатиКв('профіль:' + ід, {колір: старий_к || null, драп: старий_д || null,
                                     мірки: null, імʼя: null, згода: false});
    for (const вид of ['портрет','зріст']){
      const б = await читатиКв_('фото-' + вид);
      if (б) await писатиКв('фото-' + вид + ':' + ід, б);
    }
    await писатиКв('профілі', ПРОФІЛІ);
    await писатиКв('активний', АКТИВНИЙ);
  }
  if (!ПРОФІЛІ.some(п=>п.ід === АКТИВНИЙ)) АКТИВНИЙ = (ПРОФІЛІ[0]||{}).ід || null;
}

async function читатиАктивний(){
  if (!АКТИВНИЙ) return;
  const з = (await читатиКв_('профіль:' + АКТИВНИЙ)) || {};
  КОЛІР = Object.assign({шкіра:null,волосся:null,очі:null,кільце:null,точки:null}, з.колір||{});
  ДРАП  = Object.assign(Object.assign({}, ДОВІДНИК.показ.порожній_драп), з.драп||{});
  $('пр-імʼя').value = з.імʼя || '';
  $('пр-згода').checked = !!з.згода;
  const м = з.мірки || {};
  $('мр-зріст').value = м.зріст || '';
  for (const [ід, к] of ПОЛЯ_ОБХВАТІВ)
    $(ід).value = (м.обхвати||{})[к] || '';
  for (const [ід, к] of ПОЛЯ_АКСЕСУАРНИХ)
    $(ід).value = (м.аксесуарні||{})[к] || '';
  /* ПРОФІЛЬ СТВОРЕНО — прапорець, а не повнота: людина могла пройти два кроки
     без портрета, і тоді «чого бракує» каже це на збиранні, а не жене її знову
     через знайомство. Профілі до v4 прапорця не мають: у них створеним вважається
     той, що вже має кольори й обхвати, — інакше кожна тестувальниця проходила б
     знайомство вдруге. */
  ПРОФІЛЬ_СТВОРЕНО = !!з.створено || (!!КОЛІР.шкіра && !немаМірок());
  малюватиВирізку();
}

async function писатиАктивний(){
  if (!АКТИВНИЙ) return;
  const об = {};
  for (const [ід, к] of ПОЛЯ_ОБХВАТІВ){
    const v = parseFloat($(ід).value); if (v) об[к] = v;
  }
  await писатиКв('профіль:' + АКТИВНИЙ, {
    колір: КОЛІР, драп: ДРАП,
    імʼя: ($('пр-імʼя').value||'').trim() || null,
    згода: !!$('пр-згода').checked,
    створено: !!ПРОФІЛЬ_СТВОРЕНО,
    мірки: {зріст: parseFloat($('мр-зріст').value)||null, обхвати: об,
            аксесуарні: зібратиАксесуарні()}});
  const п = ПРОФІЛІ.find(x=>x.ід === АКТИВНИЙ);
  const нова = ($('пр-імʼя').value||'').trim();
  if (п && нова && п.назва !== нова){ п.назва = нова; await писатиКв('профілі', ПРОФІЛІ); малюватиСмугу(); }
}

