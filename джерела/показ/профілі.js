async function читатиАктивний(){
  if (!АКТИВНИЙ) return;
  const з = (await читатиКв_('профіль:' + АКТИВНИЙ)) || {};
  КОЛІР = Object.assign({шкіра:null,волосся:null,очі:null,кільце:null,точки:null}, з.колір||{});
  ДРАП  = Object.assign(Object.assign({}, ДОВІДНИК.показ.порожній_драп), з.драп||{});
  const м = з.мірки || {};
  ДАНІ_ПРОФІЛЮ_П = порожніДаніПрофіляП();
  записатиПолеПрофіляП('імʼя', з.імʼя || ''); записатиПолеПрофіляП('згода', з.згода);
  записатиПолеПрофіляП('зріст', м.зріст);
  for (const [, к] of ПОЛЯ_ОБХВАТІВ) записатиПолеПрофіляП(к, (м.обхвати||{})[к]);
  for (const [, к] of ПОЛЯ_АКСЕСУАРНИХ) записатиПолеПрофіляП(к, (м.аксесуарні||{})[к]);
  /* ПРОФІЛЬ СТВОРЕНО — прапорець, а не повнота: людина могла пройти два кроки
     без портрета, і тоді «чого бракує» каже це на збиранні, а не жене її знову
     через знайомство. Профілі до v4 прапорця не мають: у них створеним вважається
     той, що вже має кольори й обхвати, — інакше кожна тестувальниця проходила б
     знайомство вдруге. */
  ПРОФІЛЬ_СТВОРЕНО = !!з.створено || (!!КОЛІР.шкіра && !немаМірок());
  показатиПрофіль();
}

async function писатиАктивний(){
  if (!АКТИВНИЙ) return;
  await писатиКв('профіль:' + АКТИВНИЙ, {
    колір: КОЛІР, драп: ДРАП,
    імʼя: імʼяПрофіляП(),
    згода: згодаПрофіляП(),
    створено: !!ПРОФІЛЬ_СТВОРЕНО,
    мірки: міркиПрофіляП()});
  const п = ПРОФІЛІ.find(x=>x.ід === АКТИВНИЙ);
  const нова = імʼяПрофіляП();
  if (п && нова && п.назва !== нова){ п.назва = нова; await писатиКв('профілі', ПРОФІЛІ); показатиПрофіль(); }
}

/* Без зросту й чотирьох обхватів образ не збирається; `м` — мірки зрізу екрана, без нього — дані профілю. */
function немаМірок(м){
  м = м || міркиПрофіляП();
  return !м.зріст || ['плечі','груди','талія','стегна'].some(к => !м.обхвати[к]);
}

