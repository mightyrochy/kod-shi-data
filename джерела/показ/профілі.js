function записатиПолеПрофіляП(поле, значення){
  const д = ДАНІ_ПРОФІЛЮ_П;
  if (поле === 'імʼя'){ д.імʼя = значення == null ? '' : String(значення); return; }
  if (поле === 'згода'){ д.згода = !!значення; return; }
  const v = parseFloat(значення) || null;
  if (поле === 'зріст'){ д.зріст = v; return; }
  const куди = ПОЛЯ_ОБХВАТІВ.some(([, к]) => к === поле) ? д.обхвати
    : ПОЛЯ_АКСЕСУАРНИХ.some(([, к]) => к === поле) ? д.аксесуарні : null;
  if (!куди) throw new Error('профіль: нема поля «' + поле + '»');
  if (v) куди[поле] = v; else delete куди[поле];
}
/* Мірки тим самим порядком ключів, яким їх віддавали цикли по полях: пакет мосту й запис профілю лишаються ті самі. */
function міркиПрофіляП(){
  const д = ДАНІ_ПРОФІЛЮ_П, об = {}, акс = {};
  for (const [, к] of ПОЛЯ_ОБХВАТІВ) if (д.обхвати[к]) об[к] = д.обхвати[к];
  for (const [, к] of ПОЛЯ_АКСЕСУАРНИХ) if (д.аксесуарні[к]) акс[к] = д.аксесуарні[к];
  return {зріст: д.зріст, обхвати: об, аксесуарні: акс};
}
