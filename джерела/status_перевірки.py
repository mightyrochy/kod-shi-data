def _розвʼязати(п):
    """`перевірка` записана або як callable, або як ІМʼЯ функції рядком.

    ЗНАЙДЕНО НА ВЛАСНІЙ ПРАВЦІ, І ЦЕ ДЕФЕКТ САМЕ ЦЬОГО ФАЙЛУ. Три записи несли
    рядок замість функції («_слід_правил», «_пакет_без_обмежень»). `перевірити()`
    викликав рядок, ловив TypeError і клав запис у «живі» з текстом «перевірка
    впала». Тобто запис, чия перевірка ЗЛАМАНА, звітувався так само, як запис,
    чия перевірка сказала «обмеження ще діє» — у безпечний на вигляд бік.
    Це рівно та гнилизна самозвіту, проти якої написаний увесь файл: механізм,
    що мав ловити «роботу зроблено, а запис лишився», сам мовчки не працював.

    ПІСЛЯ Н-00-06/Н-V35-069 рядок — ЄДИНА форма запису: `status.py` більше не
    бачить цих функцій, бо вони живуть тут. Тобто «перевірка не знайдена» —
    тепер не екзотика, а звичайний наслідок перейменування, і `перевірити()`
    кладе такий запис у «зламані», а не в «живі».
    """
    if п is None or callable(п):
        return п
    return globals().get(str(п))


def перевірити():
    """Проганяє всі виконувані перевірки. Повертає записи, які БІЛЬШЕ НЕ ДІЮТЬ —
    тобто роботу зроблено, а список цього не помітив. Саме так самозвіт гниє."""
    застарілі, живі, без_перевірки, зламані = [], [], [], []
    for з in status.ОБМЕЖЕННЯ:
        п = _розвʼязати(з["перевірка"])
        if з["перевірка"] is not None and п is None:
            зламані.append((з["id"], "перевірка «%s» не знайдена в status_перевірки"
                            % з["перевірка"])); continue
        if п is None:
            без_перевірки.append(з["id"]); continue
        try:
            діє, деталь = п()
        except Exception as e:
            зламані.append((з["id"], f"перевірка впала: {e}")); continue
        (живі if діє else застарілі).append((з["id"], деталь))
    return dict(застарілі=застарілі, живі=живі, без_перевірки=без_перевірки,
                зламані=зламані,
                нота=("«застарілі» = обмеження знято, а запис лишився — його треба "
                      "видалити; «без_перевірки» = автоматизувати не вийшло, читати "
                      "очима; «зламані» = запис ОБІЦЯВ перевірку, і вона не працює — "
                      "це гірше за відсутність перевірки, бо виглядає як гарантія"))


