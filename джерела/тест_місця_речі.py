# -*- coding: utf-8 -*-
"""Стенд модуля `місце_речі` (корінь Е3-місце-речі, крок модуля): ярус, зони крою й «розстебнуто» в записі.

Прогін: `python3 тест_місця_речі.py` (з теки `джерела`); код виходу 1 при провалі, друкує кожну перевірку.
Читач ярусу бере три форми входу — елемент (`outfit.елементи`), річ, запис — і дає однаково; хибна форма — `ФормаВходу`.
Заміри приймання (14512): топ без рукавів з відкритим вирізом під шаром — руки й декольте «невідомо» при `видно` None,
«закрито» при 0,0, «відкрито» без шару; жилет поверх светра — різні записи для «розстебнуто» так і ні, коли джерело
знає, «невідомо», коли ні; ярус верху, низу й верхнього шару — «верх», «низ», «верх», інших — нема."""
import os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import outfit, місце_речі as МР  # noqa: E402

збої = []


def перевірити(назва, факт, чекано):
    """Друкує перевірку; збій — у перелік, прогін не обривається."""
    добре = факт == чекано
    print("%s · %s: %r%s" % ("OK " if добре else "ЗБІЙ", назва, факт, "" if добре else " (чекано %r)" % (чекано,)))
    if not добре:
        збої.append(назва)


def зони(запис):
    return {з: в["стан"] for з, в in запис["зони"].items()}


def хибна(читач, вхід):
    try:
        читач(вхід)
    except МР.ФормаВходу:
        return "ФормаВходу"
    return "відповідь"


def main():
    # 1. Ярус: верх, низ, верхній шар — факт слота; решта — None з причиною
    за_слотом = {с: МР.ярус(dict(id="р", слот=с)) for с in ("верх", "низ", "верхній_шар", "сукня", "комплект", "сережки", "взуття")}
    перевірити("ярус за слотами", за_слотом, {"верх": "верх", "низ": "низ", "верхній_шар": "верх", "сукня": None,
                                              "комплект": None, "сережки": None, "взуття": None})
    запис = МР.записати(dict(id="р", слот="сукня"))
    перевірити("ярус без факту — причина", (запис["ярус"], запис["ярус_джерело"], bool(запис["ярус_чому"])), (None, "невідомо", True))
    # 2. Три форми входу читача ярусу й хибна форма
    річ = dict(id="р", слот="верх", hex="#3a3a3a", площа=0.1)
    елемент = {е["річ"]: е for е in outfit.елементи([річ])}["р"]
    перевірити("ярус: елемент, річ, запис", [МР.ярус(ф) for ф in (елемент, річ, МР.записати(річ))], ["верх"] * 3)
    перевірити("ярус: хибні форми", [хибна(МР.ярус, х) for х in ("верх", None, [річ], {}, {"колір": "чорний"}, {"місце_речі": "верх"},
                                                            dict(МР.записати(річ), джерело="клас"))], ["ФормаВходу"] * 7)
    # 3. Зони: топ без рукавів з відкритим вирізом
    топ = dict(id="т", слот="верх", виріз="відкритий", рукав_рівень="без рукавів")
    шар = dict(id="ш", слот="верхній_шар")
    перевірити("зони без шару", зони(МР.записати(топ)), {"декольте": "відкрито", "руки": "відкрито"})
    перевірити("зони під шаром, видно None", зони(МР.записати(топ, шар)), {"декольте": "невідомо", "руки": "невідомо"})
    перевірити("зони під шаром, видно 0,0", зони(МР.записати(dict(топ, місце_стилістки=dict(видно="ні")), шар)),
               {"декольте": "закрито", "руки": "закрито"})
    перевірити("зони, видно 1,0 від стилістки", зони(МР.записати(dict(топ, місце_стилістки=dict(видно="так")), шар)),
               {"декольте": "відкрито", "руки": "відкрито"})
    перевірити("зони з маски: видно 0,0", МР.записати(dict(топ, місце_виміру=dict(видно=0.0)), шар)["зони"]["руки"]["джерело"], "вимір")
    закритий = dict(топ, виріз="закритий", рукав_рівень="довгий")
    перевірити("крій закритий — закрито й під невідомим шаром", зони(МР.записати(закритий, шар)), {"декольте": "закрито", "руки": "закрито"})
    перевірити("код крою невідомий — «невідомо», не «закрито»", зони(МР.записати(dict(id="т", слот="верх"))), {"декольте": "невідомо", "руки": "невідомо"})
    перевірити("слот без крою верху — зон нема", МР.записати(dict(id="н", слот="низ"), шар)["зони"], {})
    # 4. «Розстебнуто» шару: слово, маска, нічого; тип не дає
    светр = dict(id="с", слот="верх", виріз_тип="V-подібний")
    жилет = dict(id="ж", слот="верхній_шар", тип="жилет")
    так = dict(жилет, місце_стилістки=dict(розстебнуто="так"))
    ні = dict(жилет, місце_виміру=dict(розстебнуто="ні"))
    записи = [МР.записати(светр, ш) for ш in (так, ні, жилет)]
    перевірити("светр під жилетом: декольте за «розстебнуто» так / ні / невідомо",
               [зони(з)["декольте"] for з in записи], ["відкрито", "закрито", "невідомо"])
    перевірити("запис шару: розстебнуто й джерело", [(МР.записати(ш)["розстебнуто"], МР.записати(ш)["розстебнуто_джерело"]) for ш in (так, ні, жилет)],
               [("так", "стилістка"), ("ні", "вимір"), ("невідомо", "невідомо")])
    перевірити("зони рук не залежать від «розстебнуто»", [зони(з)["руки"] for з in записи], ["невідомо"] * 3)
    перевірити("довгий рукав шару закриває руки", зони(МР.записати(топ, dict(шар, рукав_рівень="довгий")))["руки"], "закрито")
    # 5. Колишні факти запису не зламано
    перевірити("біля обличчя: сережки й взуття", [МР.бік_межі(dict(id="р", слот=с)) for с in ("сережки", "взуття", "верх")], [True, False, None])
    print("ПІДСУМОК · збоїв %d" % len(збої))
    return 1 if збої else 0


if __name__ == "__main__":
    sys.exit(main())
