# -*- coding: utf-8 -*-
"""Стенд запису ярусу й зон; запуск з кореня: python джерела/тест_місця_речі.py."""
import copy
import sys
import unittest

import місце_речі as М


class ЗаписМісця(unittest.TestCase):
    """Приймання запису незалежно від майбутнього переведення його читачів."""

    def test_ярус_три_форми(self):
        """Елемент, річ і запис дають той самий ярус; інші слоти мають причину відсутності."""
        for слот, очікую in (("верх", "верх"), ("низ", "низ"), ("верхній_шар", "верх"),
                            ("сукня", None), ("комплект", None), ("сережки", None),
                            ("взуття", None), ("шарф", None), ("невідомий", None)):
            with self.subTest(слот=слот):
                річ = dict(id=слот, слот=слот)
                запис = М.записати(річ)
                for вхід in (річ, запис, dict(річ, місце_речі=запис)):
                    self.assertEqual(М.ярус(вхід), очікую)
                self.assertEqual(запис["ярус_джерело"], "тип" if очікую else "невідомо")
                self.assertTrue(запис["ярус_чому"])

    def test_хибна_форма(self):
        """Хибний вхід не маскується законним невідомим ярусом."""
        for вхід in (None, "верх", [], {}, {"колір": "чорний"},
                     {"місце_речі": "верх"}, dict(М.записати({"слот": "верх"}), чуже=1)):
            with self.subTest(вхід=вхід):
                with self.assertRaises(М.ФормаВходу):
                    М.ярус(вхід)

    def test_замір_14512(self):
        """Відкриті руки й декольте топа: невідомо під шаром, закрито при нулі, відкрито без шару."""
        топ = dict(id="топ", слот="верх", тип="майка", рукав_рівень="без рукавів", виріз="відкритий")
        шар = dict(id="шар", слот="верхній_шар", тип="пальто")
        for видно, очікую in ((None, "невідомо"), ("ні", "закрито")):
            річ = dict(топ, місце_стилістки=dict(видно=видно))
            запис = М.записати(річ, шар)
            self.assertEqual(запис["видно"], None if видно is None else 0.0)
            for зона in ("руки", "декольте"):
                self.assertEqual(запис["зони"][зона]["стан"], очікую)
                self.assertEqual(запис["зони"][зона]["джерело"],
                                 "невідомо" if видно is None else "стилістка")
        for зона in ("руки", "декольте"):
            self.assertEqual(М.записати(топ)["зони"][зона]["стан"], "відкрито")
        вимір = М.записати(dict(топ, місце_виміру=dict(видно=0.0)), шар)
        self.assertEqual(вимір["видно"], 0.0)
        self.assertEqual(вимір["зони"]["руки"]["джерело"], "вимір")

    def test_жилет_і_джерело_стану(self):
        """Тип жилета не визначає стан носіння, а відомий стан доходить до зони під ним."""
        светр = dict(id="светр", слот="верх", виріз="відкритий")
        жилет = dict(id="жилет", слот="верхній_шар", тип="жилет", виріз="закритий")
        for слово, стан in (("так", "відкрито"), ("ні", "закрито"), (None, "невідомо")):
            шар = dict(жилет, місце_стилістки=dict(розстебнуто=слово, слова="жилет на ній"))
            записи = М.записати_образ([светр, шар], "надворі")
            self.assertEqual(записи["жилет"]["розстебнуто"], слово or "невідомо")
            self.assertEqual(записи["жилет"]["розстебнуто_джерело"],
                             "стилістка" if слово else "невідомо")
            self.assertEqual(записи["светр"]["зони"]["декольте"]["стан"], стан)
        вимір = М.записати(dict(жилет, місце_виміру=dict(розстебнуто=False),
                               місце_стилістки=dict(розстебнуто="так")))
        self.assertEqual(вимір["розстебнуто"], "ні")
        self.assertEqual(вимір["розстебнуто_джерело"], "вимір")

    def test_крій_шару(self):
        """Безрукавний шар відкриває руки, довгий рукав закриває, частковий невідомий."""
        топ = dict(id="топ", слот="верх", рукав_слово="без рукавів")
        for рукав, очікую in (("без рукавів", "відкрито"), ("довгий", "закрито"),
                             ("короткий", "невідомо"), (None, "невідомо")):
            шар = dict(id="шар", слот="верхній_шар", рукав_рівень=рукав)
            self.assertEqual(М.записати(топ, шар)["зони"]["руки"]["стан"], очікую)

    def test_коди_крою(self):
        """Виріз, рукав і тип зберігають усі заявлені ними зони; назва не підміняє код."""
        for поля, зони in ((dict(виріз_тип="V-подібний"), {"декольте"}),
                          (dict(рукав_слово="без рукавів"), {"руки", "плечі"}),
                          (dict(тип="кроп-топ"), {"живіт"}),
                          (dict(виріз_тип="відкрита спина"), {"спина"}),
                          (dict(рукав_рівень="довгий", виріз_тип="бардо"), {"плечі"}),
                          (dict(назва="топ без рукавів з відкритою спиною"), set())):
            запис = М.записати(dict(id="річ", слот="верх", **поля))
            self.assertEqual(set(запис["зони"]), зони)
            self.assertTrue(all(ф["стан"] == "відкрито" and ф["джерело"] == "тип"
                                for ф in запис["зони"].values()))

    def test_поле_картки_не_стан(self):
        """Старе поле без підтвердження крою не стає станом застібки на ній."""
        for поле in (True, False, None):
            річ = dict(id="п", слот="верхній_шар", тип="пальто", розстібнуте=поле)
            self.assertEqual(М.записати(річ)["розстебнуто"], "невідомо")
        запис = М.записати(dict(річ, розстібнуте=True, застібка="нема"))
        self.assertEqual(запис["розстебнуто"], "так")
        self.assertEqual(запис["розстебнуто_джерело"], "тип")

    def test_невідомий_крій_і_незмінність(self):
        """Брак кодів не вигадує зони; записування не змінює вхід і не плутає сам шар із підлеглим."""
        шар = dict(id="шар", слот="верхній_шар", тип="пальто")
        речі = [dict(id="верх", слот="верх"), шар]
        до = copy.deepcopy(речі)
        записи = М.записати_образ(речі, "надворі")
        self.assertEqual(записи["верх"]["зони"], {})
        self.assertIsNone(записи["шар"]["під_шаром"])
        self.assertEqual(речі, до)
        self.assertIsNone(М.записати_образ(речі)["верх"]["під_шаром"])


def ранги_каталогу():
    """Звірити ярус запису й ранги K-BOD-02/K-SIL-03 з чинним читачем на всьому каталозі й трьох тілах."""
    import ast
    import collections
    import subprocess
    import feed as Ф
    import fit as Т
    import hypergraph as Г
    import композитор_слоти as К

    # База зафіксована нарядом: наступна частина видалить таблицю з чинного читача.
    база = subprocess.check_output([
        "git", "show", "48252dea6b263e8c654299179e0b324dc18364f9:джерела/композитор_слоти.py"
    ]).decode("utf-8")
    старі_яруси = ast.literal_eval(next(в.value for в in ast.parse(база).body
                                       if isinstance(в, ast.Assign)
                                       and any(isinstance(ц, ast.Name) and ц.id == "_ЗОНА_КРОЮ" for ц in в.targets)))
    каталог = Ф._прочитати_каталог(Ф.каталог_на_диску("каталог_повний.xml"), ліміт_фото=0)["каталог"]
    тіла = ((165, dict(плечі=112, груди=114, талія=104, стегна=114)),
            (172, dict(плечі=108, груди=96, талія=76, стегна=92)),
            (154, dict(плечі=90, груди=84, талія=64, стегна=88)))
    вад = звірок = 0
    слоти = collections.Counter()
    for зріст, обхвати in тіла:
        тіло = Т.тіло(зріст, обхвати)
        яруси = Г.крої_для_пулу(тіло) or {}
        for річ in каталог:
            слот = річ.get("слот")
            старий = старі_яруси.get(слот)
            новий = М.ярус(річ)
            слоти[слот] += 1
            вад += старий != новий
            ярус = яруси.get(новий)
            старий_ярус = яруси.get(старий)
            # Справний ранг K-BOD-02 і перевернений ярус руки 2; K-SIL-03 додає ранг вільного крою.
            вільні = dict(ярус=ярус["вільні"], оцінені=ярус["оцінені"]) if ярус else None
            for навпаки in (False, True):
                for об_єм in (None, вільні):
                    старий_ранг = К._ранг_крою(річ, старий_ярус)
                    новий_ранг = К._ранг_крою(річ, ярус)
                    if навпаки and старий_ярус:
                        старий_ранг = 2 - старий_ранг
                    if навпаки and ярус:
                        новий_ранг = 2 - новий_ранг
                    додаток = 3 * К._ранг_крою(річ, об_єм) if об_єм else 0
                    вад += старий_ранг + додаток != новий_ранг + додаток
                    звірок += 1
    print("КАТАЛОГ: речей %d, тіл %d, звірок рангів %d, розбіжностей %d"
          % (len(каталог), len(тіла), звірок, вад))
    print("СЛОТИ (на одне тіло):", {с: н // len(тіла) for с, н in sorted(слоти.items())})
    return bool(вад)


if __name__ == "__main__":
    if "--каталог" in sys.argv:
        sys.exit(ранги_каталогу())
    unittest.main(verbosity=2)
