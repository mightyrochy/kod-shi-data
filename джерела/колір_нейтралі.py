"""НЕЙТРАЛІ ОБРАЗУ: кластери одного кольору, K-COL-06 (крос-нейтралі без кроку
світлоти; два різні білі, K-PC-05 — питання про білий), K-COL-06-T (температура
нейтралі біля обличчя проти особи) і R-COL-16 (бік b* кольорової речі біля
обличчя проти очей).

ЩО ТУТ (перенесено з `колір_образу.py` без зміни жодного рядка коду, поділ
20.09.2026, рядок 95 дошки, СТАНДАРТ_КОДУ п.16; рядки — за `колір_образу.py` до
поділу, коміт d1dbd9a):
  · `кластери` (831–888) — речі одного кольору — один голос, не N;
  · `нейтралі_крос`, `білі` (894–1013);
  · `температура_нейтралі` (1431–1518) — перевіряльник напряму B, вікно бере з
    `palette.нейтраль_якір` (імпорт усередині функції, як і доти);
  · `бік_b_біля_обличчя` (1521–1584) — R-COL-16, бік рахує `palette.бік_b_проти_людини`.

Читає `колір_річ` (NEAR_МІН, SLOT_NEAR_FALLBACK) і `колір_світлота` (`_розкид`,
`реальне_вікно`, `максимум0`); фасад `колір_образу` не імпортує.
"""
import colorspace as cs
from colorspace import hx, lch, de00, reliability, MIN_TO_EMIT
from реєстр_правил import C, _зн, _сила, сила_за_корпусом
from колір_річ import NEAR_МІН, SLOT_NEAR_FALLBACK
from колір_світлота import _розкид, реальне_вікно, максимум0

def кластери(E, поріг=6.0):
    """Речі одного кольору — один голос, не N. Без цього чорна сукня і чорні човники
    давали дві однакові знахідки замість однієї (побачено на прогоні)."""
    out = []
    # ── ПЛОЩА БУВАЄ НЕВИМІРЯНА, І ЦЕ ДОКУМЕНТОВАНИЙ СТАН (07.09.2026) ────────
    # `елементи()` прямо каже: «area = r.get("площа") — None = не виміряно; не
    # підставляється нічим». Тут же стояло `-x["площа"]`, і на такому елементі
    # сортування падало TypeError: bad operand type for unary -: 'NoneType'.
    # Тобто стан, який система свідомо дозволяє й навіть боронить (не підставляти
    # вигаданої площі), валив увесь `перевірити_образ`.
    # НЕВИМІРЯНА ПЛОЩА ЙДЕ В КІНЕЦЬ ЧЕРГИ, А НЕ СТАЄ НУЛЕМ: порядок тут потрібен
    # лише щоб більша річ ставала ядром кластера. Нуль у полі `площа` кластера
    # був би вигаданим виміром — тому підсумовування нижче теж захищене.
    for e in sorted(E, key=lambda x: (x.get("площа") is None, -(x.get("площа") or 0.0))):
        for g in out:
            if de00(g["lab"], e["lab"]) <= поріг:
                g["речі"].append(e["річ"]); g["слоти"].append(e["слот"])
                # ── НАЙОБЕРЕЖНІША ПОВЕРХНЯ, А НЕ «ЯКЩО ПРИЙШЛА НЕВІДОМА» ────────
                # Коментар при створенні кластера (нижче) обіцяє: «якщо хоч одна річ
                # гладка або невідома, увесь кластер такий». Стояло ж
                # `g["текстура"] = g.get("текстура") if e.get("текстура") else None`,
                # тобто текстура знімалась ЛИШЕ за невідомої в прийшлої речі, а ГЛАДКА
                # (лак, вініл, атлас, шкіра) мовчки лишалась поза кластером: ядро
                # зберігало «вовна». Далі `нейтралі_крос` — єдиний споживач цього поля
                # в дереві — кликав `cs.de00_тканина` з текстурою кластера, дістав би
                # на парі «вовна↔вовна» kL=2 і ПОЛОВИНИВ внесок світлоти: лакова річ
                # діставала текстильну толерантність, якої R-COL-11 їй прямо не дає,
                # і знахідка гасла (Н-outfit-1-083, 11.09.2026).
                _кл, _чому_кл = cs.тканинна_пара(g.get("текстура"), e.get("текстура"))
                if _кл == 1:
                    g["текстура"] = None
                    # СВІДОК, А НЕ ТИША: без нього в діагностиці стоїть None без
                    # причини, і наступний читач не може відрізнити «зняли, бо лак»
                    # від «ніхто не міряв». Лишається ПЕРША причина — та, що зняла.
                    g.setdefault("текстура_знято_бо", _чому_кл)
                # сума лишається None, якщо хоч один член невиміряний: «частина
                # виміряна» — це не площа кластера, і видавати її за неї не можна
                g["площа"] = (None if (g["площа"] is None or e["площа"] is None)
                              else round(g["площа"] + e["площа"], 3))
                # РОЗКИД ЗОНИ ЇДЕ В КЛАСТЕР — найгірший серед членів (28.08.2026,
                # graph.py). Знайдено виміром на 850 комбінаціях: речі несли
                # розкид слова 13.8/27.5, а K-COL-06 і K-COL-02 читали кластери
                # без нього — гасіння «тонше за точність» не доїжджало нікуди.
                if e.get("розкид") and (g.get("розкид") is None or e["розкид"] > g["розкид"]):
                    g["розкид"] = e["розкид"]
                break
        else:
            out.append(dict(lab=e["lab"], L=e["L"], нейтраль=e["нейтраль"], сім_я=e["сім_я"],
                            площа=e["площа"], речі=[e["річ"]], слоти=[e["слот"]],
                            # ТЕКСТУРА ЇДЕ В КЛАСТЕР. Без неї R-COL-11 не має входу:
                            # умова «обидві поверхні тканинні» перевіряти нема на чому.
                            # Кластер однорідний за кольором, але НЕ за поверхнею, тож
                            # береться найобережніше: якщо хоч одна річ гладка або
                            # невідома, увесь кластер такий.
                            текстура=e.get("текстура"), розкид=e.get("розкид"),
                            річ="+".join([e["річ"]]), слот=e["слот"]))
    for g in out: g["річ"] = " + ".join(g["речі"])
    return out

def нейтралі_крос(E):
    """K-COL-06. Дві нейтралі на майже однаковій світлоті, але видимо різні = брудно.
    ЩО ЗМІНИЛОСЬ ПІСЛЯ ПРОГОНУ: перша версія ловила лише крос-комбінації тепла↔холодна
    і пропускала НЕЙВІ+ЧОРНИЙ — саме той приклад, який корпус називає поіменно
    («ок лише з видимою різницею світлоти»). Обидва — холодна сім'я, тож правило мовчало.
    Механізм насправді інший і не в температурі: якщо ΔL* малий, а ΔE00 великий, око
    читає «майже те саме, але не те» — помилка, а не намір. Температура лишається як
    посилення, не як умова."""
    out = []
    гр = кластери(([e for e in E if e["нейтраль"]]), поріг=6.0)
    # ── ПОРІГ ПЛОЩІ НЕ ЗАСТОСОВНИЙ ДО НЕВИМІРЯНОЇ ПЛОЩІ (07.09.2026) ─────────
    # Тут стояло `g["площа"] >= 0.10` без захисту, і на кластері без виміряної
    # площі порівняння падало TypeError. Площа `None` — документований стан
    # (`елементи`: «не виміряно; не підставляється нічим»), і саме він приходить,
    # коли образ зібрано з речей без частки площі.
    # РІШЕННЯ: невиміряний кластер ПРОПУСКАЄТЬСЯ до правила, а не відкидається за
    # порогом. Відкинути його означало б сказати «площа мала», чого ми не знаємо;
    # пропустити — застосувати колірне правило, яке площі не потребує. Ціна
    # названа: на невиміряній площі правило не може відсіяти дрібну пляму, і саме
    # для цього поріг існує. Це та сама асиметрія, що в решті файлу: краще
    # сказати зайве, ніж змовчати про те, чого не поміряв.
    гр = [g for g in гр if g["площа"] is None or g["площа"] >= 0.10]
    for i in range(len(гр)):
        for j in range(i+1, len(гр)):
            a, b = гр[i], гр[j]
            # R-COL-11: пара РІЧ↔РІЧ міряється текстильним kL=2, коли обидві поверхні
            # тканинні. Саме тут це вирішує: усі три пари, які корпус називає
            # перевернутими (графіт+чорний, білий+світло-сірий, олива+хакі), — нейтралі,
            # рознесені по L*, тобто рівно ті, що проходять цей гейт.
            dL = abs(a["L"] - b["L"])
            dE, _kL, _чому_kL = cs.de00_тканина(a["lab"], b["lab"],
                                                a.get("текстура"), b.get("текстура"))
            if dL >= C["step_min"] or dE <= 6.0: continue
            крос = a["нейтраль"] != b["нейтраль"] and "ахроматична" not in (a["нейтраль"], b["нейтраль"])
            # ── СИЛА КРОС-РОДИННОГО ШТРАФУ: strong → default ──────────────────
            # ТЕМА-4, ПРОГІН ВЕРИФІКАЦІЇ 2 (05.09.2026), дослівно: «FORCE: `default`
            # — lowered from `strong`». Підстава корпусу: теплий/холодний поділ
            # нейтралей походить від сезонного колірного аналізу (Color Me
            # Beautiful), тобто це конвенція школи, а не вимір. Раніше код видавав
            # `strong` — силу понад свій доказ.
            # ЩО ЦЕ МІНЯЄ НАД РЕАЛЬНОЮ РІЧЧЮ: пара «кемел + сірий» на однаковій
            # світлоті більше не тисне ранг як великий штраф, а лише як малий,
            # оборотний. Механізм кроку світлоти (K-COL-01, T2) не чіпаний — він
            # стоїть на вимірі Munsell і лишається на своїй силі.
            # ВНУТРІШНЬОСІМЕЙНА гілка (`soft`) не рухається: вона й так нижча.
            сила, note = _сила("default" if крос else "soft", dL, C["step_min"], _розкид(a, b))
            out.append(_зн("K-COL-06", сила,
                ("крос-комбінація теплої і холодної нейтралі без кроку світлоти" if крос else
                 "дві нейтралі на одній світлоті, але видимо різні"),
                [a["річ"], b["річ"]],
                f"ΔL*={dL:.0f} (крок не читається), але ΔE00={dE:.0f} (різниця видима): "
                f"{a['нейтраль']} проти {b['нейтраль']}",
                ремонт=f"розвести на ΔL*≥{C['step_min']:.0f} — або зблизити до тональності "
                       f"(ΔE00<6), тоді це свідомий тон-у-тон",
                запит={k: v for k, v in dict(слот=b["слот"], замість=b["річ"],
                       цільова_L_світліше=реальне_вікно(
                           [round(a["L"]+C["step_min"]+3), round(min(97, a["L"]+45))]),
                       цільова_L_темніше=реальне_вікно(
                           [round(max(2, a["L"]-45)), round(максимум0(a["L"]-C["step_min"]-3))]),
                       чому="видимий крок світлоти між двома нейтралями").items() if v},
                ламається="внутрішньосімейні пари, що майже збігаються (чорний+вугільний, "
                          "ΔE00<6), читаються як один колір — це не провал; "
                          "чорний+кемел працює саме тому, що крок великий",
                поріг=C["step_min"], вимір=dL, розкид=_розкид(a, b),
                примітка=note or None))
    return out

def білі(E, source="uncontrolled"):
    """K-COL-06, температура білого. Питання «оптичний чи вершковий» упирається в підтон
    людини — а підтон на неконтрольованому фото не стверджується (K-PC-05).
    Тому вихід тут — ПИТАННЯ людині, а не вердикт. Це і є fallback корпусу.

    ВІКНО БІЛОГО — ОДНЕ Й ЗАРЕЄСТРОВАНЕ (Н-outfit-1-087). Тут стояла своя пара меж,
    а `МАЙЖЕ_БІЛЕ` нижче несла іншу, ширшу; обидві звались «майже білим» і давали
    різні множини речей. Тепер обидві читають `C["біле_вікно"]`."""
    L_мін, C_макс = C["біле_вікно"]
    б = [e for e in E if e["L"] >= L_мін and e["C"] <= C_макс]
    if not б: return []
    R = reliability(source)
    # ── ВІСЬ ТЕМПЕРАТУРИ — ТА САМА, ЩО В `нейтраль()` (Н-outfit-1-087) ───────────
    # Стояла власна пара порогів по b*, і між ними лежала ЩІЛИНА: біле, чий b* не
    # проходив ні в теплі, ні в холодні, не належало жодній групі, тож знахідка
    # «два різні білі» на ньому не могла вийти взагалі. Реєстр уже несе цю вісь під
    # `b_нейтралі`, і коментар при ній прямо каже, що ці числа вже копіювались у
    # palette.B_НЕЙТРАЛЬ — другий дубль тієї самої осі.
    # ТРЕТЯ ГРУПА, А НЕ ЩІЛИНА: `нейтраль()` на цій самій парі має ТРИ відповіді, і
    # середня — «ахроматична». Для білого вона і є ОПТИЧНИЙ білий, тобто той самий,
    # якого знахідка нижче називає поіменно. Тому смуга між порогами — не діра, а
    # названий клас, і жодна річ вікна не лишається поза класифікацією. ЗМІРЯНО на
    # фікстурі `каталог_brief.xml`: у вікні 1746 речей — 998 теплих, 0 справді
    # холодних і 748 оптичних (b*=0.0 рівно). Тобто гілка, віддана лише парі
    # «тепле↔справді холодне», була б на цьому фіді без входу.
    теплі = [e for e in б if e["lab"][2] > C["b_нейтралі"][0]]
    холодні = [e for e in б if e["lab"][2] < C["b_нейтралі"][1]]
    оптичні = [e for e in б if C["b_нейтралі"][1] <= e["lab"][2] <= C["b_нейтралі"][0]]
    не_теплі = холодні + оптичні
    out = []
    if теплі and не_теплі:
        out.append(_зн("K-COL-06", "soft", "у образі два різні білі — вершковий і оптичний",
            [e["річ"] for e in теплі+не_теплі], "різниця температур білого читається як бруд",
            ремонт="звести до одного білого", ламається="навмисний шар (сорочка під светр) — "
                   "менша площа, менший ризик"))
    if R["undertone"] < MIN_TO_EMIT:
        out.append(dict(правило="K-PC-05", сила="питання",
            сила_нп=None, сила_нп_джерело="виміру нема: це запит елісітації, не знахідка",
            суть="який білий личить — не визначається з цього фото",
            речі=[e["річ"] for e in б],
            чому=f"надійність підтону {R['undertone']} < {MIN_TO_EMIT} для джерела «{source}»",
            питання_людині="Що на вас виглядає краще біля обличчя — оптичний білий чи вершковий/"
                           "айворі? І які метали ви носите — золото чи срібло?",
            навіщо="відповідь замінює недоступний вимір і відкриває вісь підтону",
            # ВИРОБНИК ЕЛІСІТАЦІЇ (R-PC-04: первинне джерело колориту). Раніше питання
            # ставилось і нікуди не вело — тепер поля оголошені явно, і відповідь іде в
            # той самий вхід, яким живиться вікно нейтралі.
            контракт_відповіді=dict(
                поля=dict(білий=["оптичний", "вершковий"], метал=["золото", "срібло", "обидва"]),
                куди="palette.нейтраль_якір(драп={'білий': ..., 'метал': ...}) і "
                     "суд_образу.review(драп=...)",
                статус="первинне джерело за R-PC-04; фото лишається assist зі стелею")))
    return out

def температура_нейтралі(E, F, source="uncontrolled", драп=None, мета="лестити",
                         intent="conventional", речі=None):
    """ПЕРЕВІРЯЛЬНИК для напряму B (доти був лише генератор — вікно в каталог).
    Питання, на яке відповідає: образ уже зібраний (свій гардероб, try-on) — чи не
    конфліктує нейтраль БІЛЯ ОБЛИЧЧЯ з температурою особи, і що з цим робити.

    Чому це треба окремо від генератора: генератор знає лише НАЗВИ слотів і бере
    приобличчеву вагу з таблиці-запасу; тут near ВИМІРЯНИЙ з масок (e['near']), тобто
    рішення спирається на справжню геометрію образу, а не на дефолт слота. Корпус уже
    один раз ловив цю асиметрію («генератор був суворіший за перевіряльник»).

    Вікно НЕ перерахьовується — кличеться palette.нейтраль_якір, щоб визначення
    температурного вікна лишалось одне. Сила неперервна, знахідка не блокує:
    R-CHEV-07 (інструмент під мету), R-PC-01 (слабка доказовість), R-TYP-04 (впевнений
    вердикт заборонено). За R-CHEV-08 при меті, що не є гармонізацією, вікна нема
    взагалі — отже й знахідки."""
    try:
        import palette as _P
    except Exception:
        return []
    зн = []
    for e in E:
        if not e.get("нейтраль"):
            continue
        # ── ГЕОМЕТРІЯ КОНТАКТУ Й ХРОМА РЕЧІ — ВХІД, А НЕ ЗАМОВЧУВАННЯ (Н-palette-2-101)
        # `нейтраль_якір` уміє R-CHEV-13 (індукція росте з хромою оточення) і
        # R-CHEV-15 (індукція максимальна на ЛІНІЇ КОНТАКТУ), але обидва множники
        # приходили як None і виходили як 1.0: жоден живий виклик не передавав ні
        # хроми, ні контакту, тому обидва правила були інертні на 100 % прогонів.
        # Обидва входи вже лежать під рукою: хрома — у lab самого елемента, лінія
        # контакту — у полях `виріз` і `тип`, які річ уже несе.
        _річ = next((r for r in (речі or []) if isinstance(r, dict)
                     and r.get("id") == e["річ"]), None)
        _C = lch(e["lab"])[1]
        _к, _чому_контакту = _P.контакт_із_речі(_річ or {})
        як = _P.нейтраль_якір(F, source=source, слот=e["слот"], intent=intent,
                              near=e.get("near"), драп=драп, мета=мета,
                              хрома_речі=_C, контакт=_к)
        if not як.get("придатно") or як.get("вільно"):
            continue
        b = e["lab"][2]
        db = max(0.0, як["b_min"] - b, b - як["b_max"])
        if db <= 0:
            continue
        сила_нп = round(min(1.0, db / 25.0) * як["вага_вікна"], 2)   # T3 нормування
        далекі = [s for s, v in SLOT_NEAR_FALLBACK.items() if v <= 0.2]
        # ── ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026) ────────────────
        # before: «нейтраль біля обличчя проти температури особи» — один рядок і
        # для сіро-синього шарфа на теплій особі, і для верблюжого на холодній.
        # «Проти температури» — це назва ОСІ, не бік; яку саме нейтраль шукати,
        # знав лише `ремонт` («покласти нейтраль потрібної температури»), який до
        # промпту не доїжджає, та й він каже «потрібної», не називаючи якої. Ші
        # діставала вісь без знака й ні речі, ні напряму заміни.
        # after (два справжні рядки з одного прогону):
        #   · нейтраль «шарф сіро-синій» біля обличчя холодніша за температуру
        #     особи — узяти теплішу [0.06]
        #   · нейтраль «шарф верблюжий» біля обличчя тепліша за температуру
        #     особи — узяти холоднішу [0.15]
        # Бік читається з тієї самої пари, з якої вже порахований `db` рядком вище:
        # вихід за `b_min` — холодний бік, за `b_max` — теплий. Межі лишились у `чому`.
        зн.append(dict(_зн("K-COL-06-T", "soft" if сила_нп >= C["нп_межа_soft"] else "hint",
            "нейтраль «%s» біля обличчя %s за температуру особи — узяти %s"
            % (e["річ"], "холодніша" if b < як["b_min"] else "тепліша",
               "теплішу" if b < як["b_min"] else "холоднішу"), [e["річ"]],
            "b* речі %.1f поза вікном [%.1f..%.1f]; приобличчева вага %.2f (%s), "
            "джерело підтону: %s (впевненість %.2f)" % (
                b, як["b_min"], як["b_max"], як["near"],
                "виміряно з масок" if e.get("near_виміряний") else "запасне число слота",
                як["джерело"], як["впевненість"]),
            ремонт=["покласти нейтраль потрібної температури БІЛЯ ОБЛИЧЧЯ (шарф, топ, "
                    "розстібнутий шар) — річ лишається в образі",
                    "перенести цю нейтраль далі від обличчя: " + ", ".join(sorted(далекі))],
            # СТРУКТУРОВАНО (не лише текстом): щоб шар retrieval і аудит консистентності
            # читали, ЯКУ саме вісь і в які межі тягне ремонт, а не парсили українську мову.
            запит=dict(слот="шарф|прикраси|верх", нейтраль=True,
                       цільове_b=[як["b_min"], як["b_max"]],
                       чому="нейтраль потрібної температури біля обличчя"),
            ламається="індукція біля обличчя — фізика (R-CHEV-06), але НАПРЯМ переваги "
                      "конвенція (R-CHEV-07/R-PC-01); контраст — захищеніша вісь (R-PC-03), "
                      "тому ця знахідка не має перебивати контрастні; при ненадійному "
                      "підтоні з фото сила вже обмежена стелею R-PC-04"),
            сила_нп=сила_нп, сила_нп_джерело='вимір (власний: db поза вікном b*)', db=round(db, 1),
            # ЧОМУ ВАГА САМЕ ТАКА: обидва множники, які її зменшили, названі вголос.
            # Без них стиліст бачив силу й не бачив, що приглушений колір і контакт
            # на ключиці (а не на щелепі) її вже вдвічі зняли.
            контакт_множник=як["контакт_множник"], контакт_нота=як["контакт_нота"],
            хрома_множник=як["хрома_множник"], хрома_нота=як["хрома_нота"]))
    return зн

def бік_b_біля_обличчя(E, F, речі=None, intent="conventional", мета="лестити"):
    """R-COL-16 — ПЕРЕВІРЯЛЬНИК: хроматична річ біля обличчя лежить по b* на боці,
    протилежному тому, який дає колір очей. Пара до `температура_нейтралі`
    (K-COL-06-T), яка судить нейтралі: тут — кольорові речі, і вісь та сама, b*.

    ДЖЕРЕЛО СИЛИ. Тема-2:841 (Perrett & Sprengelmeyer 2021, T2 · hint): 77 %
    обрали вищий b* до темнішого обличчя; ключ носія — очі, не ITA (тема-2 §6.1,
    K-COND-02). Один свідок на одне питання: бік рахує `palette.бік_b_проти_людини`,
    межі боку — `реєстр_правил.C["b_нейтралі"]`. Сила hint, регістр репліка, не
    блокує; `сила_нп` — з виміру (наскільки b* речі за межею боку) × приобличчева
    вага. Без входу (очей нема / b* очей у смузі) — порожньо, і про це каже пункт
    P7 чекліста палітри, а не тиша. За R-CHEV-08 при меті, що не є гармонізацією,
    напряму немає — отже й знахідки."""
    try:
        import palette as _P
    except Exception:
        return []
    if мета != "лестити":
        return []
    бб = _P.бік_b_проти_людини(F)
    if not бб.get("вхід"):
        return []
    межа_т, межа_х = C["b_нейтралі"]
    _B_ГАМУТ = (hx("#0000ff")[2], hx("#ffff00")[2])     # синій і жовтий кути sRGB
    зн = []
    for e in E:
        if e.get("нейтраль") or not e.get("lab"):
            continue
        near = e.get("near")
        if near is None:
            near = SLOT_NEAR_FALLBACK.get(e.get("слот"), 0.2)
        if float(near) < NEAR_МІН:
            continue
        b = float(e["lab"][2])
        бік_речі = _P.бік_b_речі(e["lab"])
        if бік_речі != -int(бб["бік"]):
            continue
        поріг = межа_х if бік_речі < 0 else межа_т
        z = _зн("R-COL-16", сила_за_корпусом("R-COL-16", "hint"),
            "кольорова річ «%s» біля обличчя на %s боці жовто-синьої осі, а очі дають %s"
            % (e["річ"], "холодному" if бік_речі < 0 else "теплому",
               "теплий" if бб["бік"] > 0 else "холодний"), [e["річ"]],
            "b* речі %.1f за межею боку %.1f; b* очей %.1f; приобличчева вага %.2f (%s). "
            "Напрям добору серед рівних, не заборона: одне первинне джерело, екран, не тканина"
            % (b, поріг, бб["b_очей"], float(near),
               "виміряно з масок" if e.get("near_виміряний") else "запасне число слота"),
            ремонт=["на боці очей лишити те, що біля обличчя (верх, шарф, сережки); "
                    "цю річ — далі від обличчя або з нейтральним шаром між нею і лицем"],
            # Межі інтервалу — край гамуту sRGB по b* (означення простору, не оцінка):
            # `несумісні_ремонти` перетинає інтервали числами, None там не читається.
            запит=dict(слот="шарф|прикраси|верх", нейтраль=False,
                       цільове_b=([межа_т, round(_B_ГАМУТ[1], 1)] if бб["бік"] > 0
                                  else [round(_B_ГАМУТ[0], 1), межа_х]),
                       чому="кольорова річ біля обличчя на боці b* очей"),
            ламається="одне первинне джерело (білі жінки, екран замість тканини, задача "
                      "«пасує», не «вдягну»); ключ носія — очі за Perrett 2023, ITA шкіри "
                      "боку не дає; межі боку T3 (`b_нейтралі`); при ненадійному фото очей "
                      "b* райдужки шумить так само, як b* шкіри (K-PC-05)",
            вимір=abs(b), поріг=abs(поріг))
        z["сила_нп"] = round(float(z.get("сила_нп") or 0.0) * float(near), 2)
        z["сила_нп_джерело"] = "вимір (|b*| речі за межею боку) × приобличчева вага"
        z["b_очей"] = бб["b_очей"]; z["near"] = round(float(near), 2)
        зн.append(z)
    return зн
