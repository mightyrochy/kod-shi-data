        # речей того самого слова. Вирок — лише коли ВСЕ вікно поза межами (b — найближчий
        # край); вікно, що перетинає межу, — «без входу» з названим полем, не вирок.
        # Межі — `warmer` API відношень щодо країв вікна палітри (КОЛІР-Р4, рядок 2950):
