def кластери(E, поріг=6.0):
    """Речі одного кольору — один голос, не N. Без цього чорна сукня і чорні човники
    давали дві однакові знахідки замість однієї (побачено на прогоні)."""
    out = []
    # ── ПЛОЩА БУВАЄ НЕВИМІРЯНА, І ЦЕ ДОКУМЕНТОВАНИЙ СТАН (07.09.2026) ────────
    # `елементи()` прямо каже: «area = r.get("площа") — None = не виміряно; не
    # підставляється нічим». Тут же стояло `-x["площа"]`, і на такому елементі
    # сортування падало TypeError: bad operand type for unary -: 'NoneType'.
    # Тобто стан, який система свідомо дозволяє й навіть боронить (не підставляти
    # вигаданої площі), валив увесь `перевірити_образ`.
    # НЕВИМІРЯНА ПЛОЩА ЙДЕ В КІНЕЦЬ ЧЕРГИ, А НЕ СТАЄ НУЛЕМ: порядок тут потрібен
    # лише щоб більша річ ставала ядром кластера. Нуль у полі `площа` кластера
    # був би вигаданим виміром — тому підсумовування нижче теж захищене.
    for e in sorted(E, key=lambda x: (x.get("площа") is None, -(x.get("площа") or 0.0))):
        for g in out:
            # ОДИН ГОЛОС — ЛИШЕ ДЛЯ ВИМІРІВ (рядок 141): колір зі слова — центр вікна,
            # і дві речі з тим самим словом мали ΔE 0 за побудовою. Невиміряний колір
            # тримає власний кластер (з провенансом), і пару судить уже споживач.
            # «напевно не розведені» — заперечення класу `distinct` (КОЛІР-Р4-2б, рядок 2950): «ні»
            # він каже лише на двох вимірах, тож умова «обидва — вимір» у ньому самому
            if відношення(g, e, "distinct", поріг=поріг) == "ні":
                g["речі"].append(e["річ"]); g["слоти"].append(e["слот"])
                # ── НАЙОБЕРЕЖНІША ПОВЕРХНЯ, А НЕ «ЯКЩО ПРИЙШЛА НЕВІДОМА» ────────
                # Коментар при створенні кластера (нижче) обіцяє: «якщо хоч одна річ
                # гладка або невідома, увесь кластер такий». Стояло ж
                # `g["текстура"] = g.get("текстура") if e.get("текстура") else None`,
                # тобто текстура знімалась ЛИШЕ за невідомої в прийшлої речі, а ГЛАДКА
                # (лак, вініл, атлас, шкіра) мовчки лишалась поза кластером: ядро
                # зберігало «вовна». Далі `нейтралі_крос` — єдиний споживач цього поля
                # в дереві — кликав `cs.de00_тканина` з текстурою кластера, дістав би
                # на парі «вовна↔вовна» kL=2 і ПОЛОВИНИВ внесок світлоти: лакова річ
                # діставала текстильну толерантність, якої R-COL-11 їй прямо не дає,
                # і знахідка гасла (Н-outfit-1-083, 11.09.2026).
                _кл, _чому_кл = cs.тканинна_пара(g.get("текстура"), e.get("текстура"))
                if _кл == 1:
                    g["текстура"] = None
                    # СВІДОК, А НЕ ТИША: без нього в діагностиці стоїть None без
                    # причини, і наступний читач не може відрізнити «зняли, бо лак»
                    # від «ніхто не міряв». Лишається ПЕРША причина — та, що зняла.
                    g.setdefault("текстура_знято_бо", _чому_кл)
                # сума лишається None, якщо хоч один член невиміряний: «частина
                # виміряна» — це не площа кластера, і видавати її за неї не можна
                g["площа"] = (None if (g["площа"] is None or e["площа"] is None)
                              else round(g["площа"] + e["площа"], 3))
                # РОЗКИД ЗОНИ ЇДЕ В КЛАСТЕР — найгірший серед членів (28.08.2026,
                # graph.py). Знайдено виміром на 850 комбінаціях: речі несли
                # розкид слова 13.8/27.5, а K-COL-06 і K-COL-02 читали кластери
                # без нього — гасіння «тонше за точність» не доїжджало нікуди.
                if e.get("розкид") and (g.get("розкид") is None or e["розкид"] > g["розкид"]):
                    g["розкид"] = e["розкид"]
                break
        else:
            out.append(dict(lab=e["lab"], L=e["L"], нейтраль=e["нейтраль"], сім_я=e["сім_я"],
                            колір_не_вимір=e.get("колір_не_вимір"), назва=e.get("назва"),
                            площа=e["площа"], речі=[e["річ"]], слоти=[e["слот"]],
                            # ТЕКСТУРА ЇДЕ В КЛАСТЕР. Без неї R-COL-11 не має входу:
                            # умова «обидві поверхні тканинні» перевіряти нема на чому.
                            # Кластер однорідний за кольором, але НЕ за поверхнею, тож
                            # береться найобережніше: якщо хоч одна річ гладка або
                            # невідома, увесь кластер такий.
                            текстура=e.get("текстура"), розкид=e.get("розкид"),
                            річ="+".join([e["річ"]]), слот=e["слот"]))
    for g in out: g["річ"] = " + ".join(g["речі"])
    return out

# ── УЧАСНИК K-COL-06 — НЕЙТРАЛЬ УСІМ ВІКНОМ, А НЕ ЦЕНТРОМ (КОЛІР-НЕЙТРАЛЬ, рядок 3361) ──
# ЩО БУЛО. Учасників K-COL-06 і K-COL-06-T відбирало поле елемента `нейтраль` — рід ТОЧКИ, а для
# кольору зі слова точка — центр вікна: «бежевий» (вікно від теплої нейтралі до кемелу) входив у
# правило чи ні за тим, куди впав центр. На каталозі пакета стенда з 1 158 речей-слів нейтраль
# вікном «невідомо» в 646 (центр «так» 293, «ні» 353; `проби/колір_нейтраль.py`).
# ЩО СТАЛО. Вимір — поле `нейтраль`, як доти; колір зі слова — `колір_річ.нейтраль_меж`: «так»
# — учасник, «ні» — ні, «невідомо» — «можливий»: пара з ним, яка б щось сказала (знахідка, шум,
# межі вікон), іде записом «без входу» з полем `колір_не_вимір` (п.4), а мовчазна — мовчить у
# обох варіантах (річ-колір у правило не входить, річ-нейтраль його не порушує).
def _нейтраль_межі(e):
    """«так» / «ні» / «невідомо»: чи елемент чи кластер — нейтраль K-COL-06. Вимір (і слово без
    вікна) — поле `нейтраль`, як доти; колір зі слова — усім вікном (`нейтраль_меж`)."""
    if не_вимір(e) is None or межі_кольору(e) is None:
        return "так" if e.get("нейтраль") else "ні"
    return нейтраль_меж(e) or "ні"


# ── КРОС-КОМБІНАЦІЯ — РІД АБО ПІДТОН (КОЛІР-НЕЙТРАЛЬ, рядок 3670; K-COL-12) ──
# ЩО БУЛО. «Крос» — різні роди `колір_річ.нейтраль` (тепла ↔ холодна), а рожевий беж (≤5YR) і жовтий
# беж (≥10YR) — обидва «тепла», тож їхня пара на одній світлоті йшла внутрішньосімейною гілкою
# (`soft`), хоч практики ставлять межу саме тут: Lamport — «warm beige (yellow based)… cool beige
# (pink based)», холодний рожевий «clashes with the warm camel»; Killam — рожевий беж із тоупом
# (тема-4, K-COL-12). Рід вікна слова брався з центру.
# ЩО СТАЛО. Крос — рід АБО підтон: роди — усіма точками вікна (`роди_нейтралі_меж`; вимір — точкою),
# підтон — `колір_відношення.інший_підтон` (вікно «той самий тон» практиків ΔH* ±3, K-COL-11, на
# певності тону обох — у сірого без тону підтону нема). «так» — `default`, як тепла ↔ холодна;
# «ні» чи «невідомо» — `soft` (сила щонайменше та, що стоїть на всьому вікні).
def _крос(a, b):
    """(рід, підтон) — «так» / «ні» / «невідомо» кожне: чи пара нейтралей різного роду K-COL-06
    (тепла ↔ холодна; ахроматична — не крос) і чи різного підтону (K-COL-12)."""
    ра, рб = роди_нейтралі_меж(a), роди_нейтралі_меж(b)
    if not ра or not рб:
        ра, рб = {a.get("нейтраль")}, {b.get("нейтраль")}
    вв = {x != y and "ахроматична" not in (x, y) for x in ра for y in рб}
    return ("так" if вв == {True} else "ні" if вв == {False} else "невідомо",
            _вердикт(інший_підтон(a, b)))


def нейтралі_крос(E):
    """K-COL-06. Дві нейтралі на майже однаковій світлоті, але видимо різні = брудно.
    ЩО ЗМІНИЛОСЬ ПІСЛЯ ПРОГОНУ: перша версія ловила лише крос-комбінації тепла↔холодна
    і пропускала НЕЙВІ+ЧОРНИЙ — саме той приклад, який корпус називає поіменно
    («ок лише з видимою різницею світлоти»). Обидва — холодна сім'я, тож правило мовчало.
    Механізм насправді інший і не в температурі: якщо ΔL* малий, а ΔE00 великий, око
    читає «майже те саме, але не те» — помилка, а не намір. Температура лишається як
    посилення, не як умова."""
    гр = кластери(([e for e in E if _нейтраль_межі(e) != "ні"]), поріг=6.0)
    # ── ПОРІГ ПЛОЩІ НЕ ЗАСТОСОВНИЙ ДО НЕВИМІРЯНОЇ ПЛОЩІ (07.09.2026) ─────────
    # Тут стояло `g["площа"] >= 0.10` без захисту, і на кластері без виміряної
    # площі порівняння падало TypeError. Площа `None` — документований стан
    # (`елементи`: «не виміряно; не підставляється нічим»), і саме він приходить,
    # коли образ зібрано з речей без частки площі.
    # РІШЕННЯ: невиміряний кластер ПРОПУСКАЄТЬСЯ до правила, а не відкидається за
    # порогом. Відкинути його означало б сказати «площа мала», чого ми не знаємо;
    # пропустити — застосувати колірне правило, яке площі не потребує. Ціна
    # названа: на невиміряній площі правило не може відсіяти дрібну пляму, і саме
    # для цього поріг існує. Це та сама асиметрія, що в решті файлу: краще
    # сказати зайве, ніж змовчати про те, чого не поміряв.
    гр = [g for g in гр if g["площа"] is None or g["площа"] >= 0.10]
    return _зібрати_крос(*_з_можливими([(гр[i], гр[j], _пара_нейтралей(гр[i], гр[j]))
                                         for i in range(len(гр)) for j in range(i+1, len(гр))]))


def _з_можливими(пари):
    """(пари для `_зібрати_крос`, можливі): пара, де бодай один кластер — «можливо» нейтраль
    (`_нейтраль_межі` «невідомо»), і суд її не мовчить, — у `можливі` («без входу»); мовчазна —
    геть (річ-колір у правило не входить, річ-нейтраль його не порушує)."""
    певні, можливі = [], []
    for a, b, с in пари:
        if "невідомо" not in (_нейтраль_межі(a), _нейтраль_межі(b)):
            певні.append((a, b, с))
        elif с is not None:
            можливі.append((a, b))
    return певні, можливі


def _пара_нейтралей(a, b):
    """Суд K-COL-06 над ОДНІЄЮ парою кластерів нейтралей (винесено з `нейтралі_крос` без
    зміни порогів, наряд КОЛ-2, рядок 590): None — правило мовчить; ("знахідка", z);
    ("шум", ΔE00) — пара в сірій смузі над похибкою фото; ("шум_L", ΔL*) — «одна світлота»
    не встановлюється над похибкою фото (рядок 591); ("невідомо",) — межі вікон слова.
    Пара судиться незалежно від решти образу, тож суд над образом — це сума судів над
    парами, і саме на цьому стоїть `нейтралі_крос_за_слотом`."""
    # ── ПОРІГ «ВИДИМО РІЗНІ» СТОЇТЬ НАД ПОХИБКОЮ ВХОДУ (КОЛ-1, рядок 269, 01.10.2026) ──
    # ЩО БУЛО. ΔE00 > 6 між ВИМІРЯНИМИ hex давало знахідку, хоч два кадри ОДНІЄЇ речі
    # в області правила (обидві нейтралі, ΔL* < кроку) розходяться на медіану 2.1 і p99
    # 11.5 ΔE00: 14.3 % таких пар проходили поріг 6 — правило судило шум кадру, а не
    # образ (`проби/кол1_нейтралі_шум.py`). ЩО СТАЛО. Поріг 6 — про ПРАВДИВУ різницю, а
    # виміряна відходить від неї на шум, тож твердження «видимо різні» стоїть лише
    # понад 6 + `ΔE_шум_нейтралей`, коли бодай один колір пари — вимір фото. Сіра
    # смуга між ними — запис «без входу» з полем `вимір_hex_шум` (аудит/ПРОДУКТ.md п.4), а не
    # знахідка; нижче 6 правило мовчить, як доти (змовчати — не стверджувати: той самий
    # вибір, що в K-ACC-10 після Н-4). Пара двох слів (обидва вікна) шуму фото не має.
    # Шум міряно звичайним ΔE00 (kL=1); текстильний kL=2 нижче дає різницю не більшу,
    # тож поріг для нього обережний, а не м'який.
    # R-COL-11: пара РІЧ↔РІЧ міряється текстильним kL=2, коли обидві поверхні
    # тканинні. Саме тут це вирішує: усі три пари, які корпус називає
    # перевернутими (графіт+чорний, білий+світло-сірий, олива+хакі), — нейтралі,
    # рознесені по L*, тобто рівно ті, що проходять цей гейт.
    dL = abs(a["L"] - b["L"])
    dE, _kL, _чому_kL = cs.de00_тканина(a["lab"], b["lab"],
                                        a.get("текстура"), b.get("текстура"))
    # ── ДВІ НЕЙТРАЛІ ПОРІВНЮЮТЬСЯ ЛИШЕ ЯК ВИМІР (рядок 141) ─────────────
    # Де колір кластера — центр вікна слова, ΔL* і ΔE00 — інтервали на межах
    # вікон: знахідка — коли ВСЯ пара на одній світлоті (ΔL* макс < кроку) і
    # видимо різна (найближчі краї вікон далі за 6); розведена на крок напевно
    # (ΔL* мін ≥ кроку) — законно мовчить; решта — «без входу».
    # ── «НА ОДНІЙ СВІТЛОТІ» ТЕЖ СТОЇТЬ НАД ПОХИБКОЮ ВХОДУ (КОЛ-2, рядок 591, 01.10.2026) ──
    # ЩО БУЛО. Друга умова — ΔL* < кроку — судилась на виміряних hex без похибки: поріг
    # ΔE00 після КОЛ-1 стояв над шумом, ΔL* — ні. ВИМІРЯНО (`проби/кол2_нейтралі_шум_L.py`):
    # два кадри ОДНІЄЇ нейтралі, узгоджені зі словом одне одного, розходяться на |ΔL*|
    # медіану 2.3, p95 14.9, p99 23.5 (`ΔL_шум_нейтралей`) — шум більший за сам крок 12.
    # ЩО СТАЛО. «Одна світлота» стверджується лише при ΔL* < step_min − шум, коли бодай один
    # колір пари — вимір фото; смуга до кроку — запис «без входу» `вимір_hex_шум`, а не
    # знахідка. За нинішнього шуму смуга покриває весь [0, крок): на парі з виміром фото
    # K-COL-06 не стверджує нічого, а каже «без входу» з названим полем (аудит/ПРОДУКТ.md п.4).
    # Від кроку й вище правило мовчить, як доти (змовчати — не стверджувати). Пара двох
    # слів (обидва вікна) шуму фото не має — без змін.
    _вікна = bool(не_вимір(a) or не_вимір(b))
    _шум = 0.0 if (не_вимір(a) and не_вимір(b)) else C["ΔE_шум_нейтралей"]
    _шум_L = 0.0 if (не_вимір(a) and не_вимір(b)) else C["ΔL_шум_нейтралей"]
    # Вердикти — API відношень (КОЛІР-Р4, рядок 2950): крок — `value_step`, «одна світлота над
    # шумом» — `value_step` з порогом step_min − шум, «видимо різні» — `distinct` з порогом 6 + шум.
    if _вікна:
        _крок, _dL = відношення(a, b, "value_step", міра=True)
        if _крок == "так":
            return None
        _різні, _dE = відношення(a, b, "distinct_fabric", поріг=6.0 + _шум, міра=True)
        if not (відношення(a, b, "value_step", поріг=C["step_min"] - _шум_L) == "ні" and _різні == "так"):
            return ("невідомо",)
        # встановлено на рівні вікон: у текст ідуть межі, а не центри
        dL, dE = _dL[1], _dE[0]
    # два виміри — той самий клас `distinct_fabric`, що й вікна (kL=2 текстильної пари, рядок 3082)
    elif dL >= C["step_min"] or відношення(a, b, "distinct_fabric", поріг=6.0) != "так":
        return None
    elif відношення(a, b, "distinct_fabric", поріг=6.0 + _шум) != "так":
        return ("шум", dE)
    elif dL >= C["step_min"] - _шум_L:
        return ("шум_L", dL)
    рід, підтон = _крос(a, b)
    крос = "так" in (рід, підтон)
    # ── СИЛА КРОС-РОДИННОГО ШТРАФУ: strong → default ──────────────────
    # ТЕМА-4, ПРОГІН ВЕРИФІКАЦІЇ 2 (05.09.2026), дослівно: «FORCE: `default`
    # — lowered from `strong`». Підстава корпусу: теплий/холодний поділ
    # нейтралей походить від сезонного колірного аналізу (Color Me
    # Beautiful), тобто це конвенція школи, а не вимір. Раніше код видавав
    # `strong` — силу понад свій доказ.
    # ЩО ЦЕ МІНЯЄ НАД РЕАЛЬНОЮ РІЧЧЮ: пара «кемел + сірий» на однаковій
    # світлоті більше не тисне ранг як великий штраф, а лише як малий,
    # оборотний. Механізм кроку світлоти (K-COL-01, T2) не чіпаний — він
    # стоїть на вимірі Munsell і лишається на своїй силі.
    # ВНУТРІШНЬОСІМЕЙНА гілка (`soft`) не рухається: вона й так нижча.
    сила, note = _сила("default" if крос else "soft", dL, C["step_min"], _розкид(a, b))
    return ("знахідка", _зн("K-COL-06", сила,
        ("крос-комбінація теплої і холодної нейтралі без кроку світлоти" if рід == "так" else
         "крос-комбінація нейтралей різного підтону (рожевий ↔ жовтий беж) без кроку світлоти"
         if крос else "дві нейтралі на одній світлоті, але видимо різні")
        + ("; на рівні вікон, не виміру" if _вікна else ""),
        [a["річ"], b["річ"]],
        (f"ΔL*{' щонайбільше ' if _вікна else '='}{dL:.0f} (крок не читається), але "
         f"ΔE00{' щонайменше ' if _вікна else '='}{dE:.0f} (різниця видима): "
         f"{a['нейтраль']} проти {b['нейтраль']}"
         + ("; підтон різний (той самий тон — ΔH* до 3, K-COL-12)" if підтон == "так" else "")),
        ремонт=f"розвести на ΔL*≥{C['step_min']:.0f} — або зблизити до тональності "
               f"(ΔE00<6), тоді це свідомий тон-у-тон",
        заяви=[_ВМ.заява("warm_cool_neutrals_no_step" if крос else "neutrals_same_lightness_visibly_different",
                         dl=round(dL), de=round(dE), **({"on_windows": True} if _вікна else {}))],
        ремонт_заяви=[_ВМ.заява("separate_lightness_or_tone_on_tone", step=round(C["step_min"]))],
        запит={k: v for k, v in dict(слот=b["слот"], замість=b["річ"],
               цільова_L_світліше=реальне_вікно(
                   [round(a["L"]+C["step_min"]+3), round(min(97, a["L"]+45))]),
               цільова_L_темніше=реальне_вікно(
                   [round(max(2, a["L"]-45)), round(максимум0(a["L"]-C["step_min"]-3))]),
               чому="видимий крок світлоти між двома нейтралями").items() if v},
        ламається="внутрішньосімейні пари, що майже збігаються (чорний+вугільний, "
                  "ΔE00<6), читаються як один колір — це не провал; "
                  "чорний+кемел працює саме тому, що крок великий",
        поріг=C["step_min"], вимір=dL, розкид=_розкид(a, b),
        примітка=note or None))


