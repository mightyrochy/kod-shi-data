VALUE_REL = {"echo":(0,10), "step":(22,12), "contrast":(45,18)}
def dominant_axis(samples):
    """Уздовж якої осі Lab розподіл найбільше розтягнутий. Раніше моди шукались
    ЛИШЕ по L*, тож дві моди з різницею a*=18 при однаковій світлоті зливались
    (гемоглобін дає варіацію переважно в a*, не в L*)."""
    n=len(samples)
    means=[sum(s[i] for s in samples)/n for i in range(3)]
    var=[sum((s[i]-means[i])**2 for s in samples)/n for i in range(3)]
    return max(range(3), key=lambda i: var[i]), var

def density(samples, bins=None, smooth=2, min_weight=0.10, axis=None):
    """Щільність кольору риси в Lab із вагами = частка пікселів. Без клаптиків.
    Знаходить моди по осі (за замовч. L*), не припускаючи їх кількості.
    Мода з вагою >= min_weight стає окремим ГОЛОСОМ; менша — «вкрапленням»
    (ластовиння, поодинокі сиві, вигорілі кінчики): вона реальна, але не голос."""
    if not samples: return None
    # кошики під обсяг вибірки: інакше 60 зразків у 40 кошиках = шум, і одна мода
    # хибно ділиться. ~sqrt(n), не менше 6 і не більше 40.
    if bins is None: bins=max(6, min(40, int(len(samples)**0.5)))
    if axis is None: axis,_=dominant_axis(samples)      # не завжди L*
    vals=[s[axis] for s in samples]; lo,hi=min(vals),max(vals)
    if hi-lo < 1e-6:
        m=tuple(sum(x[i] for x in samples)/len(samples) for i in range(3))
        return dict(моди=[dict(lab=m, вага=1.0, розкид=0.0)], вкраплення=[], розкид=0.0)
    w=(hi-lo)/bins
    hist=[0]*bins
    for v in vals: hist[min(bins-1,int((v-lo)/w))]+=1
    for _ in range(smooth):                      # згладжування ковзним середнім
        hist=[(hist[max(0,k-1)]+hist[k]+hist[min(bins-1,k+1)])/3 for k in range(bins)]
    peaks=[k for k in range(1,bins-1) if hist[k]>=hist[k-1] and hist[k]>hist[k+1] and hist[k]>0]
    # ── КРАЙОВІ КОШИКИ ТЕЖ ПІКИ (24.08.2026) ──────────────────────────────────
    # ДЕФЕКТ, ЗНАЙДЕНИЙ НА ВХОДІ «БАЛАЯЖ»: два щільні кластери (корені L*18, кінці
    # L*55) сидять у ПЕРШОМУ й ОСТАННЬОМУ кошиках, а пошук піків ішов лише по
    # внутрішніх — тож двоколірне волосся ЗАВЖДИ зливалось в одну моду L*≈33, якої
    # в жодному пасмі нема (відтворено на 8 і на 200 зразках, і з перехідними
    # тонами). Наслідок: хибний контраст особи, хибний «її чорний». Підтримка «волосся
    # може бути двома кольорами» не працювала для найчастішого випадку — корені
    # темніші за кінці. Западина (VALLEY) далі вирішує, чи це справді дві моди.
    if bins >= 2 and hist[0] > hist[1] and hist[0] > 0: peaks=[0]+peaks
    if bins >= 2 and hist[bins-1] > hist[bins-2] and hist[bins-1] > 0: peaks=peaks+[bins-1]
    if not peaks: peaks=[max(range(bins), key=lambda k:hist[k])]
    # злити піки без справжньої западини: бімодальність вимагає, щоб мінімум між
    # піками був помітно нижчим за менший із них (інакше це брижі згладжування)
    VALLEY = 0.65        # T3: западина має бути <65% меншого піка
    merged=[peaks[0]]
    for pk in peaks[1:]:
        prev=merged[-1]; valley=min(hist[prev:pk+1])
        if valley < VALLEY*min(hist[prev],hist[pk]): merged.append(pk)
        elif hist[pk]>hist[prev]: merged[-1]=pk
    peaks=merged
    centers=[lo+(k+0.5)*w for k in peaks]
    groups={c:[] for c in centers}
    for s_ in samples:
        c=min(centers, key=lambda c: abs(s_[axis]-c)); groups[c].append(s_)
    modes=[]
    for c,g in groups.items():
        if not g: continue
        m=tuple(sum(x[i] for x in g)/len(g) for i in range(3))
        sd=(sum((x[axis]-m[axis])**2 for x in g)/len(g))**0.5
        modes.append(dict(lab=m, вага=len(g)/len(samples), розкид=round(sd,1)))
    modes.sort(key=lambda d:-d["вага"])
    srt=sorted(vals); q=lambda p: srt[min(len(srt)-1,int(p*len(srt)))]
    return dict(моди=[m for m in modes if m["вага"]>=min_weight],
                вкраплення=[m for m in modes if m["вага"]<min_weight],
                вісь="Lab"[axis] if axis<3 else "?", вісь_індекс=axis,
                розкид=round(q(0.9)-q(0.1),1))          # робастно, не max-min

def підтон_риси(a, b, h):
    """Словесний підтон ОДНІЄЇ риси з (a*, b*, h).

    ВИНЕСЕНО В ОДНЕ ТІЛО ПІСЛЯ ПАДІННЯ НА РЕАЛЬНОМУ ВХОДІ. Цей вираз стояв
    голим усередині `features`, а `перерахувати_рису` — друга точка, що будує
    ті самі поля риси, — його просто не мала. Наслідок був не косметичний:
    `feature_spectrum` читає `f["undertone"]` без `.get`, тож будь-яка риса,
    додана через `перерахувати_рису`, валила `spectra_by_feature`,
    `palette.тон_від_рис` і `palette.специфікація` з KeyError.

    ЩО ЦЕ ЛАМАЛО В ПРОДУКТІ: `bridge._features` саме так і додає другий, третій
    тон волосся. Тобто **будь-яка жінка з мелірованим, балаяжним, відрослим або
    сивіючим волоссям** не отримувала палітри взагалі — `bridge.палітри` падав.
    На однотонному волоссі все працювало, і жоден стенд проєкту цього не бачив,
    бо всі профілі батарей однотонні.

    Задача-42 §5 стверджувала протилежне: «механічно це вже можливо —
    `перерахувати_рису` додає рису, і `spectra_by_feature` підхопить її сама».
    Перевірено прогоном: не підхоплює, а падає. Тепер підхоплює."""
    return ("оливковий" if (a < 6 and b > 2.2 * max(a, 1e-6)) else
            "рожевий/холодний" if h < 35 else
            "жовтий/теплий" if h < 70 else "нейтральний")


def поля_риси(lab, kind=None, lex=None):
    """ВСІ похідні поля однієї риси з (L,a,b). ОДНЕ тіло на всі точки, що рису будують.

    ЧОМУ ЦЕ ОКРЕМА ФУНКЦІЯ (клас дефекту, третій екземпляр).
    Рису будували ДВА місця — `features()` і `перерахувати_рису()` — двома
    незалежними наборами полів. Розбіжність між ними вже коштувала продукту
    двічі, і обидва рази однаково: людина з НЕОДНОТОННИМ волоссям не діставала
    палітри взагалі, бо друга риса приходила з іншим набором ключів.

      · перший раз бракувало `undertone` -> KeyError у feature_spectrum
        (полагоджено винесенням `підтон_риси` в одне тіло);
      · другий раз розійшовся `warmth`: `features` рахує cos(h−60) БЕЗУМОВНО,
        `перерахувати_рису` — тільки коли тон визначений, інакше None. Виміряно
        08.09.2026 наскрізним прогоном:

            bridge.палітри({волосся: ["#6b4b2e", "#b4b4b4"], ...})
            -> palette.специфікація -> palette.тон_від_рис -> cs.resonance
            -> TypeError: unsupported operand type(s) for -: 'float' and 'NoneType'

        Тобто **жінка з сивиною або попелястим пасмом не діставала палітри** —
        рівно той самий продуктовий наслідок, що й першого разу.

    Полагодження екземпляра лишало клас. Тому тепер точка одна.

    `warmth` для риси без тону — None, а не число: cos(h−60) на ахроматичній рисі
    рахує кут, який сам модуль оголосив шумом округлення (ACHROMATIC_C). Нуль там
    був би твердженням «рівно нейтральна», якого ніхто не міряв.
    """
    L, C, h = lch(lab)
    a, b = lab[1], lab[2]
    поля = dict(describe(lab, kind, lex))
    тон_є = поля.get("h") is not None
    поля.update(a=a, b=b, a_star=a,
                undertone=підтон_риси(a, b, h),
                warmth=(math.cos(math.radians(h - 60)) if тон_є else None))
    return поля


def features(lab_skin, lab_hair, lab_eye, lab_glasses=None,
             from_photo=False, protocol="uncontrolled", lex=None):
    """from_photo=True: волосся корегується виміряним зсувом (Grimes'09), шкіра —
    НЕ корегується (інша фізика), натомість несе невизначеність за протоколом."""
    # Волосся МОЖЕ бути двома кольорами (балаяж, мелірування) — це різні пасма.
    # Шкіра НЕ може: ластовиння, рум'янець, засмага — це текстура однієї шкіри,
    # а не друга шкіра. Тому дроблення на голоси дозволене лише для волосся.
    SPLITTABLE = {"волосся"}
    def _voices(nm, val):
        """Точка -> один голос. Набір зразків -> моди; на голоси дробиться лише
        те, що може бути двома різними матеріалами."""
        if not (isinstance(val,(list,tuple)) and val and isinstance(val[0],(list,tuple))):
            return {nm: val}, None
        d=density(val)
        if nm not in SPLITTABLE:
            # усі моди понад головну — вкраплення, хай яка їхня вага
            main=(max(d["моди"], key=lambda m:(round(m["вага"],2), m["lab"][0] if nm=="очі" else 0)) if d["моди"] else None)
            out={nm: (main["lab"] if main else val[0])}
            # ── K-ECHO-01 / Zyla (24.08.2026): КІЛЬЦЕ РАЙДУЖКИ — окрема риса, не заміна «очі».
            # Складне око (сіро-зелене тіло + темне лімбальне кільце, бурштиновий обідок)
            # раніше зводилось до головної моди. Zyla: кільце райдужки = «свій чорний»
            # (формальна темна нейтраль). «очі» лишається тілом райдужки (головна мода),
            # тож outfit.контраст_особи, що читає F["очі"] як одну рису, не міняється;
            # темніша мода з вагою ≥ 0.10 стає F["очі_кільце"].
            if nm=="очі" and main and len(d["моди"])>=2:
                темна=min(d["моди"], key=lambda m:m["lab"][0])
                if темна is not main and темна["lab"][0] < main["lab"][0]-8.0:
                    out["очі_кільце"]=темна["lab"]
            if main:
                d=dict(d, вкраплення=[m for m in d["моди"] if m is not main and m["lab"] is not out.get("очі_кільце")]+d["вкраплення"],
                       моди=[main]+([m for m in d["моди"] if m["lab"] is out.get("очі_кільце")]))
            return out, d
        if len(d["моди"])<=1:
            base=d["моди"][0]["lab"] if d["моди"] else val[0]
            return {nm: base}, d
        out={}
        srt=sorted(d["моди"], key=lambda m:-m["lab"][0])
        for k,m in enumerate(srt):
            out[f"{nm}_{'світле' if k==0 else 'темне' if k==len(srt)-1 else f'сер{k}'}"]=m["lab"]
        return out, d
    dists={}
    parts={}
    for nm,val in (("шкіра",lab_skin),("волосся",lab_hair),("очі",lab_eye),("оправа",lab_glasses)):
        if val is None: continue
        v,d = _voices(nm,val); parts.update(v)
        if d: dists[nm]=d
    # Волосся з фото більше не зсувається; несе невизначеність за протоколом.
    hair_unc = hair_photo_uncertainty(protocol) if from_photo else None
    hair_parts=parts
    F={}
    for nm,lab in hair_parts.items():
        if lab is None: continue
        kind = ("волосся" if nm.startswith("волосся")
                else "очі" if nm.startswith("очі") else nm)
        F[nm] = поля_риси(lab, kind, lex)
    # ШКІРА: ITA підключено до рекомендацій (раніше було мертвим кодом)
    if "шкіра" in F:
        sp = skin_pos(hair_parts.get("шкіра", lab_skin),
                      protocol=protocol if from_photo else None)   # розв'язана трійка, не сирий вхід
        F["шкіра"].update(ITA=sp["ITA"], depth_band=list(sp["band_p"])[0],
                          band_p=sp["band_p"], p_olive=sp["p_olive"],
                          photo_note=sp.get("photo_note"))
        # CONTINUUM-МАГНІТУДА ПІДТОНУ (замість cos(h-60) як ДРАЙВЕРА рішення про температуру).
        # Сила = знакова відстань h° обличчя від нейтрального центру, масштабована на розкид.
        # Числа виміряні (див. довідку): лицьова шкіра h°≈56-60°, не-афр. діапазон 45-69°;
        # тому центр 57°, розкид ~±12°. Вище центру = жовтіше/тепліше (h°->90, b* росте);
        # нижче = червоніше/холодніше (h°->0, a* просвічує). Драйвер — b* (a* обличчя інваріантне
        # між людьми — виміряно Wang/Xiao), h° — безпечний зведений вимір.
        # Це САМОВІДНОСНА величина (наскільки жовтіша за типову шкіру) — калібрування проти
        # драпіровки НЕ треба; поріг «наскільки сильна, щоб діяти» — продуктове рішення.
        # ХРОМАТИЧНА ПЛОЩИНА a*b*: warm-cool, хрома(clarity) І олива — з ОДНІЄЇ точки ОДНОЧАСНО,
        # замість двох окремих ліній. L* (глибина) ортогональна, лишається окремо (ITA/depth_band).
        # Один виклик замість вкладеного блоку: warm-cool/олива/clarity живуть у
        # _температура_шкіри(), тож profile.py може перерахувати їх після правки профілю.
        F["шкіра"].update(_температура_шкіри(hair_parts.get("шкіра", lab_skin)))
    if hair_unc:
        for k in F:
            if k.startswith("волосся"): F[k]["L_невизначеність"] = hair_unc
    if dists: F["_розподіли"]={k:dict(моди=len(v["моди"]),
                                      вкраплення=[dict(вага=round(x["вага"],3),
                                                       L=round(x["lab"][0],1)) for x in v["вкраплення"]],
                                      розкид=v["розкид"]) for k,v in dists.items()}
    # hair_corrected=bool(from_photo) було ПРЯМОЮ НЕПРАВДОЮ: from_image() вимкнено,
    # волосся зсувом не коригується (див. hair_photo_uncertainty). Метадані мусять
    # казати те, що сталось, інакше наступний шар вирішує на вигаданому статусі.
    F["_meta"]=dict(from_photo=from_photo,
                    hair_corrected=False,
                    skin_corrected=False,
                    корекції="жодних: обидві риси несуть невизначеність, а не зсув",
                    tier=tier("hair_nat_L","olive"))
    return F

def _температура_шкіри(lab):
    """ЄДИНЕ місце, де рахується warm-cool/олива/clarity шкіри. Винесено з features(),
    щоб profile.py міг ПЕРЕРАХУВАТИ похідні поля після правки (засмага, фарбування):
    доти L/a/b мінялись, а ITA, тепло_сила й undertone лишались від старого кольору,
    і palette.температура судила шкіру, якої вже нема."""
    L, C, h = lch(lab)
    _a, _b = lab[1], lab[2]
    _C = (_a*_a + _b*_b) ** 0.5
    _Ц_ПІДТ, _Р_ПІДТ = ЦЕНТР_ПІДТОНУ, РОЗКИД_ПІДТОНУ
    if C < ACHROMATIC_C:
        return dict(
            тепло_сила=None, тепло_клас="не визначено",
            тепло_центр=_Ц_ПІДТ, тепло_розкид=_Р_ПІДТ,
            хрома_шкіри=round(_C, 1), олива_член=None,
            undertone="н/д (хроми шкіри нема)",
            олива_основа="не рахувалась: тону нема",
            причина_без_температури=(
                "хрома шкіри C*%.1f < %.1f: кут тону не визначений, температура НЕ "
                "стверджується (ймовірно ч/б кадр, промах маски або недоекспозиція)"
                % (_C, ACHROMATIC_C)))
    _сила = max(-1.5, min(1.5, (h - _Ц_ПІДТ) / _Р_ПІДТ))   # ВІСЬ 1: warm-cool (h°, b*-керована)
    # ВІСЬ 2 у ТІЙ ЖЕ площині — олива як РЕГІОН: теплий(жовтий) бік + ПРИГЛУШЕНО.
    # Золото = насичений жовтий (велика C*), олива = приглушений жовтий (мала C*):
    # вікно ТОНУ (57-67°) × вікно ХРОМИ (20-27) відсікає золото від оливи, чого 1D-кут не міг.
    _олива = round(soft(h, 57., 67., 3.) * soft(_C, 20., 27., 3.), 2)
    # ── ЗНАК ОСІ ПРИДУШЕНИЙ, ПОКИ ВІН НЕ ВИМІР (реєстр: undertone_anchor, T4) ──
    # Той самий хід, що `провенанс_високого_стегна` в areas: величина лишається,
    # ТВЕРДЖЕННЯ, яке на ній стоїть, мовчить. Магнітуда |тепло_сила| самовідносна й
    # виживає; знак на цій популяції не населений, тому класу не буде.
    _в = вісь_підтону_двостороння()
    _м = МЕЖА_КЛАСУ_ПІДТОНУ
    _клас = ("тепла" if _сила > _м else "холодна" if _сила < -_м else "нейтральна")
    _підтон = ("жовтий/теплий" if _сила > _м else
               "рожевий/холодний" if _сила < -_м else "нейтральний")
    if not _в["двостороння"]:
        _клас = "не стверджується (вісь одностороння на цій популяції)"
        _підтон = ("оливковий" if _олива >= 0.33 else
                   "не стверджується: знак осі не калібрований")
    return dict(
        тепло_сила=round(_сила, 2),
        тепло_клас=_клас,
        вісь_знак_придатний=_в["двостороння"],
        вісь_односторонність=(None if _в["двостороння"] else _в),
        тепло_центр=_Ц_ПІДТ, тепло_розкид=_Р_ПІДТ,
        тепло_якір_тір=REGISTRY["undertone_anchor"]["t"],
        хрома_шкіри=round(_C, 1), олива_член=_олива,
        undertone=("оливковий" if _олива >= 0.33 else _підтон),
        олива_основа=("площина a*b*: теплий(жовтий)+приглушено(мала хрома)=олива; хрома дає "
                      "сигнал, якого не мав 1D-кут. АЛЕ хрома чутлива до ББ (K-PC-05), і "
                      "олива/золото перекриваються -> членство мʼяке; вирішення=елісітація"))


# Макіяж — риси, які людина ОБРАЛА, а не має. Імена з префіксом, щоб жоден
# наявний фільтр їх не проковтнув мовчки: `контраст_особи` і
# `face_contrast.value_обличчя` шукають ключі на «волосся», `домінантність` —
# точні «шкіра»/«очі». Помада, що потрапила б у будь-який із них, тихо змінила б
# контраст особи, тобто ВИМІР людини, а вона його не змінює — вона змінює те,
# скільки контрасту людина може винести біля обличчя (K-CLR-03).
МАКІЯЖ_РИСИ = ("губи", "повіки", "рум'яна")
ПРЕФІКС_МАКІЯЖУ = "макіяж_"


def додати_макіяж(F, макіяж):
    """Кольори макіяжу — ОКРЕМИМИ рисами профілю, кожна зі своїм голосом.

    ЧОМУ ОКРЕМИМИ, А НЕ ОДНИМ ЧИСЛОМ. Те саме, що вже вирішено для волосся:
    кожна риса — свій голос, риси не усереднюються. Помада й тіні лежать у
    РІЗНИХ місцях кола тонів, і середнє між винно-червоним і сірувато-синім не
    описує жодного з них. `spectra_by_feature` підхоплює нову рису сам, тож
    кожен колір макіяжу дає власну дугу.

    ⚠ ГОЛОВНЕ ОБМЕЖЕННЯ, І ВОНО НЕ ТЕХНІЧНЕ. Шкіра, волосся й очі — ДАНІ: вони
    в людини є. Помада — ОБРАНА: це рішення, яке вже ухвалене, і воно саме може
    бути невдалим. Якщо дати дузі помади ту саму силу, що й дузі шкіри, система
    підбиратиме одяг під сьогоднішню помаду з тією ж упевненістю, з якою
    підбирає під шкіру, — і закріпить помилку, якщо помада не та. Тому риса
    несе `рід="обрана"`, і кожен рядок у фід із неї підписаний окремо: шар вище
    має право її зняти. Це не UI-дрібниця: без цієї позначки вихід не можна
    прочитати чесно.

    ⚠ ЧОГО ЦЕ НЕ РОБИТЬ: не міряє, чи ПАСУЄ сама помада. Такого правила в
    корпусі нема, і вигадувати його тут не можна (сила ≤ верифікація).

    Приймає dict {"губи": "#hex", ...}, або hex одним рядком (=губи), або
    легасі-прапорець (bool / "яскравий" / "немає"), який кольору не несе й тому
    рис не створює — лише важіль контрасту K-CLR-03 нижче по течії."""
    if not макіяж:
        return F, {}
    # ── СЛІД У ПРОФІЛІ (19.09.2026): `F["_макіяж"]` — нормоване слово ─────────
    # Важіль K-CLR-03 читають три місця (ранг основ, вікно біля обличчя, суд
    # K-CLR-02), і всі три дістають людину як `outfit.контраст_особи(F)` — без
    # сліду в F вікно й суд макіяжу не бачили, а ранг бачив (йому макіяж передавав
    # `bridge._основи` окремим аргументом): та сама людина в трьох місцях мала два
    # контрасти. Ключ із підкресленням — як `_розподіли`/`_meta`: обхідники рис
    # такі ключі пропускають. Нюд/«немає» сліду не лишає — важеля нема.
    import face_contrast as _KC
    _рівень = _KC.рівень_макіяжу(макіяж)
    if _рівень:
        F = dict(F)
        F["_макіяж"] = dict(рівень=_рівень,
                            **({"губи": макіяж} if isinstance(макіяж, str) and макіяж.strip().startswith("#")
                               else {з: h for з, h in (макіяж.items() if isinstance(макіяж, dict) else ())
                                     if з in МАКІЯЖ_РИСИ and isinstance(h, str) and h.strip().startswith("#")}))
    якщо_рядок = isinstance(макіяж, str)
    if якщо_рядок and not макіяж.strip().startswith("#"):
        return F, {}                      # легасі-прапорець: кольору нема
    if якщо_рядок or not isinstance(макіяж, dict):
        макіяж = {"губи": макіяж} if якщо_рядок else {}
    додані = {}
    for зона in МАКІЯЖ_РИСИ:
        hexx = макіяж.get(зона)
        if not hexx or not str(hexx).strip().startswith("#"):
            continue
        lab = hx(hexx)
        імʼя = ПРЕФІКС_МАКІЯЖУ + зона
        F = перерахувати_рису(F, імʼя, lab, kind="макіяж")
        F[імʼя] = dict(F[імʼя], рід="обрана", зона=зона, hex=hexx)
        додані[зона] = dict(імʼя=імʼя, hex=hexx, L=round(lab[0], 1))
    return F, додані


def перерахувати_рису(F, риса, lab, kind=None, lex=None):
    """Після зміни (L,a,b) риси ВСІ похідні поля мусять перерахуватись з нового кольору.
    Знайдено розбором: profile.засмага рухала L* 61.3->47.8, а ITA лишалась 33.2
    ('intermediate') замість -6 ('brown'), і тепло_сила показувала дозасмажну шкіру."""
    F = dict(F)
    старий = dict(F.get(риса) or {})
    kind = kind or ("волосся" if риса.startswith("волосся") else риса)
    нове = dict(старий)
    нове.update(поля_риси(lab, kind, lex))
    if kind == "шкіра":
        sp = skin_pos(lab)
        нове.update(ITA=sp["ITA"], depth_band=list(sp["band_p"])[0],
                    band_p=sp["band_p"], p_olive=sp["p_olive"])
        нове.update(_температура_шкіри(lab))
    F[риса] = нове
    return F

# R-COL-05 — дубль `colorspace.RELATIONS`: відношення тону — фіча, не вирок.
RELATIONS = {"analogous":(0,30), "complementary":(180,30), "split":(150,22),
             "triadic":(120,25), "tonal":(0,12)}

def _arc(c,half):
    """Дуга (c − half, c + half) по модулю 360."""
    return ((c-half)%360, (c+half)%360)
def _in_arc(h,a):
    """Чи кут h лежить у дузі a, з переходом через 0°."""
    lo,hi=a; return (lo<=h<=hi) if lo<=hi else (h>=lo or h<=hi)

# R-MUN-03 — дубль `colorspace.feature_spectrum`: хрома — самостійна вісь, не похідна value.
def feature_spectrum(f, intent):
    """Спектр ДОЗВОЛЕНОГО від ОДНІЄЇ риси. Ахроматична риса тонових дуг НЕ дає."""
    off,w = RELATIONS[intent]
    if not f.get("тон_визначений", True):
        hues=[]                       # сиве/нейтральне: голосує лише світлотою й хромою
    else:
        hues=[_arc((f["h"]+off)%360, w)] + ([_arc((f["h"]-off)%360, w)] if off not in (0,180) else [])
    # світлота: три легітимні відношення до риси, не одне
    Lr={k:(max(0,f["L"]-c-wd), min(100,f["L"]-c+wd)) for k,(c,wd) in VALUE_REL.items()}
    Lr.update({k+"+":(max(0,f["L"]+c-wd), min(100,f["L"]+c+wd)) for k,(c,wd) in VALUE_REL.items() if c})
    return dict(риса=None, тон=hues, світлота=Lr,
                хрома=(max(0,f["rel_C"]-0.28), min(1,f["rel_C"]+0.32)),
                температура=f["warmth"], підтон=f["undertone"])

def spectra_by_feature(F, intent):
    """Спектр дозволеного (`feature_spectrum`) для кожної риси профілю, крім службових з `_`; поле
    `риса` — ім'я."""
    out={}
    for nm,f in F.items():
        if nm.startswith('_'): continue
        sp=feature_spectrum(f,intent); sp["риса"]=nm; out[nm]=sp
    return out

def _розсіяння(vals, ваги=None):
    """НЕПЕРЕРВНЕ зважене розсіяння (СКВ) — замість max−min. Використовує ВСІ точки й ваги
    (площа/надійність), не дві крайні. Повертає (σ, μ)."""
    if not vals: return (None, None)
    ваги = ваги or [1.0]*len(vals)
    S = sum(ваги) or 1.0
    μ = sum(w*x for x, w in zip(vals, ваги)) / S
    σ = (sum(w*(x-μ)**2 for x, w in zip(vals, ваги)) / S) ** 0.5
    return (σ, μ)

def _кут_розсіяння(hs_deg, ваги=None):
    """КРУГОВЕ зважене розсіяння тону (замість max-парного гепу). R=довжина результуючого
    вектора (1=зібрані, 0=розкидані); кутова СКВ = sqrt(-2·ln R). Неперервне, по всіх рисах."""
    if not hs_deg: return None
    ваги = ваги or [1.0]*len(hs_deg)
    S = sum(ваги) or 1.0
    Cc = sum(w*math.cos(math.radians(h)) for h, w in zip(hs_deg, ваги)) / S
    Ss = sum(w*math.sin(math.radians(h)) for h, w in zip(hs_deg, ваги)) / S
    R = (Cc*Cc + Ss*Ss) ** 0.5
    return round(math.degrees((-2*math.log(max(R, 1e-9))) ** 0.5), 1)

# R-COL-10 — дубль `colorspace.регіони`: колір міряється по регіонах, не середнім по кадру.
def регіони(F, source="uncontrolled"):
    """Кожна риса (шкіра/волосся/очі) — РЕГІОН у CIELAB: центр + розкид + ФОРМА + СИЛА-як-якір,
    не точка. Плюс АНСАМБЛЬ — НЕ літеральний перетин (він порожній, бо риси в різних місцях
    простору), а ХМАРА всіх трьох: центроїд зважений ПЛОЩЕЮ + дисперсія по осях (=контраст) —
    «як одне ціле обличчя». Ші-стиліст працює і від кожного регіону окремо (ехо кожної риси з
    її широтою й вагою), і від ансамблю (яка людина як ціле + внутрішні напруги).
    Розкид/форма/площа є лише коли їх дав вимір (зонний шлях); інакше None — чесно."""
    рел = reliability(source)
    розп = F.get("_розподіли", {}) or {}
    пікс = F.get("_пікселі", {}) or {}
    def _C(f):
        """Хрома риси з полів a, b (0, коли їх нема)."""
        a, b = f.get("a", 0.0), f.get("b", 0.0); return (a*a + b*b) ** 0.5
    риси, хмара = {}, []
    for nm in ("шкіра", "волосся", "волосся_біля_обличчя", "очі"):
        f = F.get(nm)
        if not f or "L" not in f: continue
        центр = (f["L"], f.get("a", 0.0), f.get("b", 0.0))
        d = розп.get(nm, {}) or {}
        розкид = f.get("внутрішній_контраст")
        if розкид is None: розкид = d.get("розкид")
        моди = d.get("моди")
        мульти = (len(моди) > 1) if isinstance(моди, (list, tuple)) else (isinstance(моди, int) and моди > 1)
        # сила-як-якір = ЧИСТА сила: специфічність(хрома) × тіснота(1−розкид). НЕ множимо на
        # надійність виміру — то окрема вісь (як у ансамблі). Це «наскільки специфічна риса».
        хр = min(1.0, f.get("rel_C", 0.0) / 0.5)
        тіс = 1.0 if not розкид else max(0.15, 1.0 - min(розкид, 20.0) / 20.0)
        # h=None у ахроматичної риси (сиве/попелясте волосся, C*<2) — це НЕ нуль градусів,
        # це «тону нема». round(None) валив увесь ансамбль, і контраст_особи ловив падіння
        # своїм except, звітуючи «регіони недоступні» — тобто цілий шар мовчки вмирав.
        _h = f.get("h")
        риси[nm] = dict(
            центр=tuple(round(x, 1) for x in центр),
            h=(round(_h) if _h is not None else None),
            тон_визначений=(_h is not None), C=round(_C(f), 1),
            розкид=(round(розкид, 1) if розкид else None),
            форма=("мультимодальна" if мульти else "уніфікована"),
            якір_сила=round(хр * тіс, 2), площа_пікс=пікс.get(nm),
            echo_діапазон=("широкий: риса дає кілька законних ехо (напр. база+мелірування)"
                           if мульти else "вузький: одне точне ехо"))
        if nm != "волосся_біля_обличчя":                 # не рахувати обрамлення двічі в хмарі
            хмара.append((nm, центр, пікс.get(nm)))
    if len(хмара) < 2:
        return dict(риси=риси, ансамбль=None, примітка="замало рис для ансамблю")
    # АНСАМБЛЬ — центроїд зважений ПЛОЩЕЮ (шкіра домінує зір), дисперсія по осях = контраст
    ваги = [(pl if pl else 1.0) for _, _, pl in хмара]; S = sum(ваги)
    центроїд = tuple(round(sum(w * c[i] for (_, c, _), w in zip(хмара, ваги)) / S, 1) for i in range(3))
    Ls = [c[0] for _, c, _ in хмара]
    Cs = [(c[1] ** 2 + c[2] ** 2) ** 0.5 for _, c, _ in хмара]
    hs = [math.degrees(math.atan2(c[2], c[1])) % 360 for _, c, _ in хмара]
    # value-КОНТРАСТ = пара ВОЛОССЯ↔ШКІРА (несуча, corpus/Lamport). Очі НЕ в L-контрасті —
    # інакше темні очі роблять світлу блондинку «висококонтрастною» (хибно). Очі — в h/C нижче.
    # Це РІЗНИЦЯ двох групових середніх (неперервна), НЕ max−min.
    hair_Ls = [f["L"] for k, f in F.items()
               if k.startswith("волосся") and not k.startswith("_") and "L" in f]
    skin_L = (F.get("шкіра") or {}).get("L")
    value_к = (round(abs(sum(hair_Ls)/len(hair_Ls) - skin_L), 1)
               if hair_Ls and skin_L is not None else None)
    відомі = any(pl for _, _, pl in хмара)
    домінанта = (max(хмара, key=lambda t: (t[2] or 0))[0] if відомі else "шкіра (за замовч. площею)")
    # РОЗСІЯННЯ — НЕПЕРЕРВНЕ зважене (СКВ / кругове), НЕ max−min: усі риси й ваги, не дві крайні.
    σC, _ = _розсіяння(Cs, ваги)
    σL, _ = _розсіяння(Ls, ваги)
    hσ = _кут_розсіяння(hs, ваги)
    # «ВПЕВНЕНІСТЬ» тут = СИЛА властивості (репрезентація для стиліста: НАСКІЛЬКИ тепла/контрастна
    # людина), НЕ надійність виміру. Неперервно, сигмоїдою (soft), 0..1; тепло — знакове.
    # Центри/ширини сигмоїд — T3 (орієнтир, де «слабко/помірно/сильно»), не калібровані.
    def _sig(x, c, w):
        """Логістична сила властивості 0..1 з центром c і шириною w, округлена до сотих; центри й
        ширини — T3."""
        return round(1/(1+math.exp(-(x-c)/w)), 2)
    тепло_особи = (F.get("шкіра") or {}).get("тепло_сила")   # −1.5..+1.5 знакова сила warm/cool
    сила = dict(
        тепло=тепло_особи,                                              # знакова: −холод .. +тепло
        тепло_наскільки=(round(abs(тепло_особи), 2) if тепло_особи is not None else None),
        контраст=(_sig(value_к, 33., 12.) if value_к is not None else None),   # 0..1 наскільки контрастна (волосся↔шкіра)
        хрома_контраст=(_sig(σC, 5., 3.) if σC is not None else None),         # 0..1 наскільки різна насиченість рис
        темп_напруга=(_sig(hσ, 22., 12.) if hσ is not None else None))        # 0..1 наскільки риси різні за тоном
    # надійність ВИМІРУ — ОКРЕМО (не «впевненість» стиліста): чи можна вірити числам вище.
    підтримка = 1/(1+math.exp(-(len(хмара)-2.0)/0.5))
    надійність_виміру = round(reliability(source).get("chroma", 0.5) * підтримка, 2)
    ансамбль = dict(
        центроїд=центроїд, домінанта_площі=домінанта, площі_відомі=відомі,
        сила=сила,                                           # <- РЕПРЕЗЕНТАЦІЯ для стиліста
        сирі=dict(value=value_к, C_σ=(round(σC,1) if σC is not None else None),
                  h_σ=hσ, L_σ_усі=(round(σL,1) if σL is not None else None)),  # сирі числа під силою
        надійність_виміру=надійність_виміру,                 # <- ОКРЕМО: чи вірити числам
        сенс=("сила = наскільки виражена кожна вісь (тепло/контраст/хрома-контраст/темп-напруга) — "
              "це читає стиліст; сирі = самі числа розсіяння (неперервна СКВ, не max−min); "
              "надійність_виміру — окремо: якість фото, не сила властивості"))
    return dict(риси=риси, ансамбль=ансамбль,
                примітка="ансамбль = ХМАРА трьох регіонів (НЕ перетин — він порожній), зважена площею")

def _arc_overlap(a,b,step=2):
    """Перетин двох дуг. РАНІШЕ повертав (pts[0], pts[-1]) — і на перетині ЧЕРЕЗ 0°
    (напр. 345..15) віддавав (0, 358), тобто майже все коло замість вузької дуги.
    Перегук читався як «риси сходяться скрізь». Тепер шукається розрив у списку:
    якщо він є, дуга обгортається через нуль."""
    pts=[h for h in range(0,360,step) if _in_arc(h,a) and _in_arc(h,b)]
    if not pts: return None
    if len(pts)==1: return (pts[0], pts[0])
    розриви=[i for i in range(1,len(pts)) if pts[i]-pts[i-1] > step]
    обгортка = (pts[0] < step) and (pts[-1] >= 360-step) and розриви
    if обгортка:
        i=розриви[-1]                     # хвіст перед розривом — початок дуги
        return (pts[i], pts[i-1])
    return (pts[0], pts[-1])

def resonance(F, intent):
    """Де спектри РІЗНИХ рис перегукуються — і де розходяться. Без злиття в бал.

    ВІСЬ ТЕМПЕРАТУРИ ПРОПУСКАЄТЬСЯ, КОЛИ ХОЧ ОДНА РИСА БЕЗ ТОНУ. Ахроматична
    риса (сиве пасмо, попелясте волосся, C* нижче ACHROMATIC_C) не має кута тону,
    отже не має й температури. Раніше тут стояло беззастережне віднімання, і
    сива риса валила весь виклик TypeError — а з ним `palette.тон_від_рис`,
    `palette.специфікація` й `bridge.палітри`, тобто ВЕСЬ палітрний вихід для
    людини з сивиною. Пара без спільної осі не мовчить: вона їде в
    `без_температури` з причиною, бо «не порівнювали» і «порівняли й однаково» —
    різні відповіді."""
    SP=spectra_by_feature(F,intent); names=list(SP)
    echoes=[]; tensions=[]; без_т=[]
    for i in range(len(names)):
        for k in range(i+1,len(names)):
            n1,n2=names[i],names[k]
            ov=[o for a in SP[n1]["тон"] for b in SP[n2]["тон"] if (o:=_arc_overlap(a,b))]
            t1, t2 = SP[n1]["температура"], SP[n2]["температура"]
            dT = None if (t1 is None or t2 is None) else abs(t1-t2)
            if dT is None:
                без_т.append(dict(риси=(n1,n2),
                                  чому="одна з рис ахроматична: тону нема, отже нема й "
                                       "температури. Вісь не порівнюється — це не «однакові»"))
            if ov: echoes.append(dict(риси=(n1,n2), спільні_дуги=ov,
                                      Δтемпература=(round(dT,2) if dT is not None else None)))
            if dT is not None and dT>0.6:
                tensions.append(dict(риси=(n1,n2), Δтемпература=round(dT,2),
                                     суть="різні температури — не усереднювати",
                                     вісь="undertone"))
            dC=abs(SP[n1]["хрома"][0]-SP[n2]["хрома"][0])
            if dC>0.25: tensions.append(dict(риси=(n1,n2), Δхрома=round(dC,2),
                                           суть="різні рівні чистоти"))
    # зони, де сходяться ≥3 риси (не бал, а перелік учасників)
    conf={}
    for h in range(0,360,5):
        who=[nm for nm,sp in SP.items() if any(_in_arc(h,a) for a in sp["тон"])]
        base=sorted({nm.split("_")[0] for nm in who})      # фракції -> одна риса
        if len(base)>=3: conf.setdefault(tuple(base),[]).append(h)
    return dict(перегуки=echoes, напруги=tensions, без_температури=без_т,
                зони_збігу={",".join(k):(v[0],v[-1]) for k,v in conf.items()})

def relation_coverage(F, step_h=2, step_L=8, rels=(0.15,0.35,0.55,0.75), min_votes=2):
    """ДАНІ, не вердикт: яку частку gamut охоплює кожне відношення для цієї особи.
    Без ok/PASS/FAIL — рішення ухвалює шар вище. Крок дрібний: дуги бувають вужчі
    за грубу сітку (моя попередня сітка 20° давала хибний нуль на дузі 24°)."""
    grid=[(L, c_max(L,h)*r*math.cos(math.radians(h)), c_max(L,h)*r*math.sin(math.radians(h)))
          for L in range(15,95,step_L) for h in range(0,360,step_h) for r in rels]
    out={}
    for rel in RELATIONS:
        n=sum(1 for lab in grid
              if sum(1 for v in feature_votes(F,lab,rel).values() if v["тон"]=="так")>=min_votes)
        out[rel]=round(n/len(grid),3)
    return out

