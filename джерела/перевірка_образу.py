# -*- coding: utf-8 -*-
"""ПЕРЕВІРКА ОБРАЗУ — два входи шва між кодом і стилісткою: `підготувати` (пакет перед вибором)
і `перевірити_образ` (знахідки над обраним образом), з посадкою (`_посадка`).

ЧОМУ ОКРЕМИЙ МОДУЛЬ (наряд 3.3, К-4). Доти обидва входи жили у фасаді `pipeline` — разом із
реекспортом пакета моделі, паспорта, розбору відповідей і вердикту. Самі вони стоять нижче:
кличуть суди образу, палітру, силует, посадку й аксесуари, а не модель. Композитор
(`композитор_оцінка`) імпортував `pipeline` вгорі файла заради `перевірити_образ`, а пакет
моделі кличе композитор — так фасад замикав цикл через усю модельну частину. Тепер
композитор імпортує цей модуль, а `pipeline` реекспортує ті самі функції.

Код перенесено дослівно з `pipeline.py` (входи шва — розділи «ПЕРЕД ВИБОРОМ» і «ПІСЛЯ ВИБОРУ»)."""
import status
import внутрішня_мова as _ВМ
import outfit as O
import palette as P
import profile as PR
import реєстр_правил as _РЕЄСТР
import суд_образу as _СУД
import формальність as _ФОРМ
import регістр_уваги as _РУ_М
import дистанція as _ДИСТ
import trace as _СЛ_IO
import outer as _ВШ0
import accessory as АК
import реєстри as _РЕ
import language_gate as МГ
import знахідка as ЗН
import palettes as _ПЛ_ба
import fit as ПС
import silhouette as СЛ
import feed
import colorspace as _cs


def підготувати(F, слоти=("верх", "низ", "взуття", "сумка"), source="uncontrolled",
                каталог=None, шлях_фіду=None, ліміт_фото=None,
                intent="conventional", якір_тон=None, фокус=None, драп=None,
                самозвіт=None, мета=None, мета_слова=None, мета_зони=None, прикраси=None, зріст_см=None,
                нагода=None, місце=None, формат=None, дрес_код=None, година=None,
                господар=False, креативне=False, роль=None, супутник_рівень=None,
                активність=None, сезон=None, темп_c=None, тіло=None,
                жорстке_ні=None, ваги_цілей=None,
                життєвий_перехід=None, форма_повна=True, lex=None, явні_схеми=(),
                відкриті_зони=None, зарезервований_колір=None, ошатність=None, гілка_ошатності=None,
                насиченість=None):
    """Пакет для ші-стиліста: хто ця людина, що просить нагода, які палітри законні,
    які реальні речі під кожне вікно, і чого система не знає.

    `явні_схеми` — схеми палітри, названі ВИКЛИКАЧЕМ поіменно (вибір жінки на
    екрані палітри). Гейт наміру в `palette.розвилка` вирішує, що код радить сам;
    названу гілку він не скасовує, тож вона доїжджає до розвилки пакета — а отже
    й до пулу, який будується саме за нею.

    `каталог` — уже виміряний список SKU (feed.прогін().каталог-подібний) АБО
    `шлях_фіду` — YML магазину, тоді фід міряється тут. Без жодного з них пакет
    віддається БЕЗ кандидатів і чесно це каже: вікна без каталогу — це припущення,
    що така річ існує."""
    _PR = PR

    особа = O.контраст_особи(F, source)
    if not особа.get("доступно"):
        return dict(готово=False, чому=особа.get("чому"),
                    що_робити="потрібні шкіра й волосся в профілі (colorspace.features)")

    # `ошатність` — смуга паспорта (число мовної моделі): та сама, якою ріжеться пул, тож бриф
    # (`occasion_level`, маркер щабля) каже те саме число, що й пул.
    сцен = _ФОРМ.сценарій(місце=місце, код=_ФОРМ.код_дрес(дрес_код), година=година,
                          господар=господар, креативне=креативне, роль=роль,
                          супутник_рівень=супутник_рівень, активність=активність,
                          сезон=сезон, нагода=нагода, темп_c=темп_c,
                          відкриті_зони=відкриті_зони, зарезервований_колір=зарезервований_колір,
                          смуга=_ФОРМ.смуга_ошатності({"ошатність": ошатність, "дрес_код": дрес_код}),
                          гілка=гілка_ошатності, формат=формат)

    # ── ВАГИ ЦІЛЕЙ → МЕТА ───────────────────────────────────────────────────
    # Ваги дають мету, яку вміють читати palette.нейтраль_якір і посадка.краї. Усереднення
    # по тижневому міксу нагод (`мікс_нагод`, ключі плиток) не потрібне: його слав
    # лише CLI `run_outfit.py`, а ключ нагоди тлумачать паспорт і мовний шар.
    # ── МЕТА ЗІ СЛІВ ПРО ЦЕЙ ВИХІД ПЕРЕВАЖАЄ ВАГИ ПРОФІЛЮ ───────────────────
    # Рішення власника: мета — «питання сценарію, а не профілю». Паспорт випадку
    # несе її (`паспорт_нагоди.СХЕМА_ПАСПОРТА["мета"]`, лише зі слів жінки), шов
    # доставляє як поле нагоди (`сценарій.ПОЛЯ`). Коли слів не було — як доти:
    # дефолт із ваг, і `чому_мети` чесно каже, що це не її вибір.
    _мета_ваг, _чому_ваг_мети = _PR.мета_з_ваг(ваги_цілей)
    _причини_мети = []
    # Зона («відвести погляд від…») — окрема плитка з будь-якою увагою, мету всього образу не
    # гасить; старий запис «приховати» + зона приходить сюди вже переведеним (`паспорт_нагоди.мета_на_осі`).
    if мета in _PR.МЕТИ:
        _причини_мети.append(_ВМ.заява("goal_from_her_words", goal=_ВМ.код("goal", мета),
                                     weights_goal=_ВМ.код("goal", _мета_ваг), rule="K-IO-02", source="model", choice="conversation"))
    else:
        мета = _мета_ваг
    чому_мети = dict(statements=_причини_мети + _чому_ваг_мети["statements"])

    # ── САМОЗВІТ ЇДЕ ПОРУЧ ІЗ ДРАПОМ, А НЕ ЗАМІСТЬ НЬОГО (Н-V03-007) ──────────
    # Це два РІЗНІ канали з однієї відповіді людини: `драп` читає `нейтраль_якір`
    # (вікно b* нейтралі), `самозвіт` — `palettes.осі` (бік осі тону). Доти другий
    # каналу до палітри не мав узагалі: параметра не було ні тут, ні в
    # `розвилка_специфікацій`, ні в `специфікація`, тож `palettes.осі` на живому
    # шляху завжди утримувала вісь (undertone 0.15 < MIN_TO_EMIT на uncontrolled)
    # і віддавала ОБИДВІ температурні версії кожної сім'ї — 347° з 360.
    # ── ВІДСТАНЬ ОГЛЯДУ ВХОДИТЬ У ДОБІР, А НЕ ЛИШЕ В СУД (K-COND-04) ─────────
    # ЩО ЦЕ МІНЯЄ. `нейтраль_якір` множить приобличчеву вагу слота на силу підтону
    # і з добутку виводить ШИРИНУ вікна b* нейтралі — того самого, що їде запитом
    # у каталог (`запит_у_фід`). Доти вага слота була одна на всі нагоди, тобто
    # запит до каталогу не відрізняв вечерю за столом від весілля на повний зріст.
    # Тепер відрізняє: на «розмові» вікно нейтралі біля обличчя вужчає (пул
    # суворіший саме там, де людину роздивляються), на «повний зріст» ширшає, а
    # далекі слоти — навпаки. `формат` оголошений у `сценарій.ПОЛЯ` і приїжджає
    # сюди тим самим шляхом, що `місце` й `нагода`; коли жодне з трьох у таблицю
    # не веде, `дистанція` = None і добір лишається таким, яким був.
    _дист = _ДИСТ.з_сценарію(dict(місце=місце, формат=формат, нагода=нагода))
    розв = P.розвилка_специфікацій(F, list(слоти), source=source, intent=intent,
                                   якір_тон=якір_тон, фокус=фокус, драп=драп, мета=мета,
                                   самозвіт=самозвіт, дистанція=_дист.get("дистанція"),
                                   явні=явні_схеми, насиченість=насиченість)

    # ── реальні речі під вікна ────────────────────────────────────────────────
    # ── ЖОРСТКЕ «НІ» — АБСОЛЮТНИЙ ФІЛЬТР, І ВІН МУСИТЬ СТОЯТИ ДО ВІКОН ────────
    # Тема-6 PART 12 називає це найочевидніше правильним правилом теми, якому доти не
    # було де жити. Фільтр стоїть ПЕРЕД покриттям навмисно: інакше вікно рахувало б
    # кандидатів, яких людина не вдягне, і «порожньо=False» брехало б. Скільки саме
    # відкинуто — їде в пакет, бо це і є ціна списку заборон.
    кат, звіт_фіду, відкинуто_ні = каталог, None, []
    # СЛІД ПОРУЧ ІЗ ПОЛЕМ: поле каже читачеві виходу, чиє це рішення, запис —
    # логові, на чому воно спрацювало (скільки речей прибрано і за яким словом).
    # Запис стоїть ПІСЛЯ фільтра, нижче, бо число до фільтра ще не існує.
    if кат is None and шлях_фіду:
        зфід = [г["запит_у_фід"] for г in розв["розвилка"] if г.get("запит_у_фід")]
        звіт_фіду = feed.прогін(шлях_фіду, зфід, ліміт_фото=ліміт_фото)
        кат = звіт_фіду.get("каталог")
    if кат and жорстке_ні:
        кат, відкинуто_ні = _PR.жорстке_ні_фільтр(кат, жорстке_ні)
        # Застава тут не потрібна: `trace` — модуль ядра, `запис` тотальний,
        # і ловилась тут лише помилка коду в `%`-підстановці вище. Ковтання лишало
        # лог без K-PER-05 — тобто без рядка про те, СКІЛЬКИ речей прибрано жорстким
        # «ні» людини, — і мовчало про це. Летить у `bridge.виклик` → `помилка` + `код`.
        _СЛ_IO.запис("K-PER-05", "sensory_limit_absolute_filter",
                      "підготувати", значення="%d речей прибрано за %s"
                      % (len(відкинуто_ні), ", ".join("«%s»" % x for x in жорстке_ні)),
                      сила=1.0, напрям="фільтр каталогу, не оцінка")
    for г in розв["розвилка"]:
        q = г.get("запит_у_фід")
        if not q: continue
        if кат:
            г["кандидати"] = feed.покриття(q, кат, словник=lex)
            г["порожніх_вікон"] = sum(1 for r in г["кандидати"] if r["порожньо"])
        else:
            г["кандидати"] = None
            г["порожніх_вікон"] = None

    # ── ЩО ШУКАТИ ПО ФОРМІ (парне до колірної розвилки) ───────────────────────
    # Доти пакет казав стилістові, які КОЛЬОРИ шукати, і мовчав про крій та довжину.
    # ЧОМУ ЦЕ ТЕПЕР ЗА ПРАПОРЦЕМ. Виміряно на стенді: `специфікація` — 93% часу
    # всього виклику «запити» (1.20 с із 1.29 на CPython, ×2 бо рука C рахується
    # на донорському тілі). У Pyodide на телефоні це 4–6 с чекання на випадок.
    # При цьому єдине, що з неї доживало до брифа, — один рядок про довжину
    # верху: ранжування кроїв віддає `гіперграф.простір` за 0.03 с, і воно
    # неперервне, а не бінарне. Повна сітка потрібна шару retrieval (запит у
    # фід по 1485 комбінаціях), а не брифу — тому вона лишається доступною,
    # але вимикається там, де її ніхто не читає.
    форма = None
    if тіло is not None and форма_повна:
        форма = СЛ.специфікація(тіло, intent=intent, мета=мета)

    # ── чого бракує на вході ──────────────────────────────────────────────────
    аудит = PR.аудит(F, source=source, зріст_см=зріст_см, драп=драп, нагода=нагода,
                     сценарій_входи=dict(місце=місце, година=година, господар=господар,
                                         супутник_рівень=супутник_рівень,
                                         активність=активність))
    # СЛІД ПОРУЧ ІЗ ПОЛЕМ, А НЕ ЗАМІСТЬ НЬОГО (K-IO-02, друге проходження гейта).
    # Поле `бракує_входів.правило` нижче каже ЧИТАЧЕВІ ВИХОДУ, чиє це рішення;
    # запис тут каже ЛОГОВІ, на чому воно спрацювало — на скількох порожніх полях
    # профілю. Два різні споживачі (`trace.py`: «запис читає ЛОГ, знахідку читає
    # споживач»), і одного замість двох тут не досить: без числа лог не може
    # відрізнити «питань нема, бо профіль повний» від «шар не викликався».
    # Застава тут не потрібна: `trace` — модуль ядра, `запис` тотальний.
    # Ковталась лише помилка коду вище, а разом з нею — саме та відмінність, заради
    # якої цей запис і стоїть (абзац над ним): «питань нема, бо профіль повний»
    # проти «шар не викликався». Летить у `bridge.виклик` → `помилка` + `код`.
    _СЛ_IO.запис("K-IO-02", "ask_exactly_what_is_missing", "підготувати",
                 значення="%d питань онбордингу, %d полів «не питати»"
                 % (len(аудит.get("бракує_онбордингу") or []),
                    len(аудит.get("не_питати") or {})),
                 сила=None, напрям="протокол браку даних")
    # КОНТРАКТ_ПРИНТУ тут нарешті щось вирішує: він каже, які входи правил принту
    # існують, а які ні — стиліст бачить, які правила замовкнуть, ще до вибору речей
    контракт_принту = {k: v for k, v in P.КОНТРАКТ_ПРИНТУ.items()
                       if v["статус"] == "НЕМА ВИМІРУ"}

    return dict(
        готово=True,
        особа=dict(**особа, температура=P.температура(F, source, intent),
                   бік_b=P.бік_b_проти_людини(F),      # R-COL-16: рядок жінці в brief
                   масштаб=PR.масштаб(зріст_см) if зріст_см else None,
                   гейт_джерела=_cs.gate_conclusions(
                       source, se_L=особа.get("розкид"))),     # R-PC-10: регіональний шум профілю
        сценарій=сцен,
        # ВІДСТАНЬ ОГЛЯДУ ЇДЕ В ПАКЕТ РАЗОМ ІЗ ПРИЧИНОЮ (K-COND-04). Не для
        # краси: пакет — це те, що бачить шар пояснень, і «вага приобличчя
        # ключована на розмову» та «вага одна на всі сцени, бо місця не сказали»
        # — два різні стани, які без цього поля виглядали б однаково.
        дистанція=_дист,
        палітри=розв,
        форма=форма or dict(проганялось=False,
                            чому="не передано тіло — крій і довжина не виводяться"),
        каталог_звіт=(dict(офферів=звіт_фіду["офферів"], з_кольором=звіт_фіду["з_кольором"],
                           відкинуто_контролем=звіт_фіду["відкинуто_контролем"],
                           без_слота=звіт_фіду["без_слота"],
                           розкид_каталогу=звіт_фіду["розкид_каталогу"])
                      if звіт_фіду else None),
        людина=dict(
            # ── ФІЛЬТР НАЗИВАЄ СВОЄ ПРАВИЛО (K-PER-05, друге проходження гейта) ──
            # ЩО ЦЕ МІНЯЄ (правило 3, before/after). Сенсорне обмеження ЛОВИТЬСЯ
            # й ПРАЦЮЄ: `profile.жорстке_ні_фільтр` предикатом над виведеним полем
            # `каблук` відкидає 1 028 пар із 1 950 на «не ношу підбори»
            # (`проби/per_K-PER-05.py`). Чого у виході не було — ID: ні тут, ні в
            # гейті `перевірити_образ`. Отже правило з найтвердішою силою теми-6
            # («hard on the person's authority alone») міняло КАТАЛОГ і в жодному
            # рядку виходу себе не називало.
            # ID СТОЇТЬ БІЛЯ ЧИСЛА, А НЕ НАД УСІМ БЛОКОМ: у `людина` лежать
            # різні речі (жорстке «ні», ваги цілей, життєвий перехід), і одне
            # `правило` над ними приписало б K-PER-05 ще й ваги.
            жорстке_ні_правило="K-PER-05",
            жорстке_ні=list(жорстке_ні or []),
            відкинуто_за_жорстким_ні=len(відкинуто_ні),
            # ПОЛЕ ЗВЕТЬСЯ «ПРИКЛАДИ», І П'ЯТЬ — ЙОГО ЗМІСТ, А НЕ СТЕЛЯ ЗВІТУ
            # Повне число стоїть рядком вище
            # (`відкинуто_за_жорстким_ні`), тож перелік нічого не ховає.
            приклади_відкинутих=відкинуто_ні[:5],
            ваги_цілей=ваги_цілей,
            життєвий_перехід=життєвий_перехід,
            мета=мета, чому_мети=чому_мети, цитата_мети=мета_слова,
            # `прикраси` — бажання про метал прикрас З ЦИМ ОБРАЗОМ зі слів
            # жінки. Без нього добір слота прикрас іде за рекомендацією температури
            # (`палітра_температура`), а суд K-COL-06-M звіряє лише з драпіровкою
            # профілю — і це названо тут, а не вдається, ніби вхід є.
            прикраси=прикраси,
            нема_входів=[k for k, v in (("жорстке_ні", жорстке_ні),
                                        ("ваги_цілей", ваги_цілей),
                                        ("прикраси", прикраси)) if not v],
            чому_важить="тема-6 PART 12: без цих полів шар елісітації не має де "
                        "жити. `жорстке_ні` — абсолютний фільтр (річ не показується "
                        "взагалі), `ваги_цілей` — ваги. Порожні поля "
                        "означають, що правила теми-6 мовчать, а не що обмежень нема"),
        # ── K-TIME-01: «ПЕРЕМІРЯТИ, А НЕ ПЕРЕНАЗВАТИ» ЇДЕ РАЗОМ ІЗ БРАКОМ ────
        # `profile.аудит` рахує ще два поля — `переміряти` (риси, чий ЗАЯВЛЕНИЙ зсув
        # перевищив поріг: перефарбування, сивина, засмага) і `вимога` (що саме
        # робити), — і вони не входили в жоден вихід узагалі. Це виконувана форма
        # K-TIME-01: зміна волосся вимагає НОВОГО ВИМІРУ, а не нової мітки, бо далі
        # вікна каталогу рахуються на числі, якого ніхто не бачив. Поле рахувалось
        # і вмирало разом із викликом.
        # ── КАНАЛ НАЗИВАЄ СВОЄ ПРАВИЛО (друге проходження гейта досяжності) ──
        # Поле має їхати назовні й називати правило: інакше правило мовчить.
        # У виході НЕ СТОЯЛО
        # «K-IO-02» — ні тут, ні в `bridge`, ні в показі. Тобто читач виходу
        # бачив вісім питань і не мав як дізнатися, ЧИЄ це рішення й на якій
        # підставі їх рівно вісім; а гейт досяжності чесно рахував правило таким,
        # що себе не називає (`проби/io_K-IO-02.py` друкує сам канал, але ID у
        # ньому був лише в докстрінгу проби).
        # ЧОМУ ПОЛЕМ, А НЕ ЗНАХІДКОЮ. Знахідка — це вирок над РІЧЧЮ; тут вироку
        # нема й бути не може: список питань адресований тому, хто веде діалог, і
        # `реєстр_сила.зн` над ним дав би рядок, з яким людина нічого не
        # зробить (та сама межа, по якій K-COMP-01 у `зведення.py`).
        бракує_входів=dict(правило="K-IO-02",
                           онбординг=аудит.get("бракує_онбордингу"),
                           не_питати=аудит.get("не_питати"),
                           переміряти=аудит.get("переміряти"),
                           вимога_переміряти=аудит.get("вимога"),
                           правила_принту_без_виміру=контракт_принту),
        обмеження=status.список(),
        як_читати=(
            "ВИБІР РЕЧЕЙ — ЗА ВАМИ. Код не ранжує палітри й не зводить знахідки в бал: "
            "кожна гілка — законна, ваги ПОРЯДКОВІ, не виміряні. `кандидати` кажуть, де "
            "вікно порожнє в РЕАЛЬНОМУ каталозі (тоді або ширше вікно, або інша гілка). "
            "`форма` — дзеркало палітр по осі крою: що шукати, а не що виправляти; "
            "її поле `роздільність` каже, наскільки цей фільтр насправді звужує простір. "
            "`обмеження` — чого числа не знають; читати перед тим, як довіряти силі. "
            "Зібравши образ, віддайте його в перевірити_образ() — там знахідки й ремонти."))


def перевірити_образ(F, речі, source="uncontrolled", тіло=None,
                     вето_покриття=None, тон_колготи=None, жорстке_ні=None,
                     реагенти=None, тривалість_год=None, поверхня=None,
                     гардероб=None, заявлена_колона=False, **kw):
    """Ші-стиліст обрав речі — тут вони перевіряються. Повертає і сирий review, і
    контракт виходу (`для_стиліста`), і результат інваріанта (`перевірити_контракт`):
    обидва були написані й нікому не потрібні, бо ланцюжка не існувало.

    `тіло` — вихід посадка.тіло(зріст, обхвати[, рівні_см]). Коли він переданий і речі
    несуть свої висоти (верх_см/низ_см із розмірної таблиці), додатково проганяється
    шар посадки й силуету. Без тіла шар мовчить і каже це вголос: колірний вердикт над
    річчю, яка не сидить, — саме той провал, від якого рулбук ставить посадку в P0.
    Знахідки посадки їдуть ОКРЕМИМ ключем, а не в стани: вони не залежать від того,
    надворі людина чи в приміщенні, і змішувати дві різні осі в один список означало б
    втратити цю різницю."""
    # ── ТЕПЛОВИЙ ВНЕСОК СТАВИТЬСЯ ДО review, І ЦЕ НЕ ДЕТАЛЬ ПОРЯДКУ ───────────
    # ЗНАЙДЕНО ПРОГОНОМ: перша версія рахувала його поруч із рештою гілки теми-11,
    # тобто ПІСЛЯ `суд_образу.review` — і K-WEA-01 устигав порахувати тренч штукою, а
    # виправлення приїжджало до вже виданої знахідки. Число входить у лічбу шарів,
    # отже мусить стояти раніше за того, хто рахує.
    # ТЕПЛОВА МІТКА ТИПУ ЇДЕ РАЗОМ ІЗ ЧИСЛОМ. Число каже, СКІЛЬКИ
    # шару дає цей верх; мітка — ЧИМ він є на осі тепла («тепло» / «частково» /
    # «майже ні» / «ні», `верхнє_погода.ТЕПЛОВІ_ФУНКЦІЇ`). Відколи смуга −8…+2 просить
    # 2,5 шару замість 3,5, лічба штук більше не ловить «куртка замість пальта в
    # мороз» — це питає `суд_погода` саме за міткою, і без неї воно мовчить (погода
    # не вигадується). Тут, а не в судді: внесок і мітка — одна властивість речі й
    # мусять приїхати одним кроком, раніше за того, хто рахує.
    _тф0 = _ВШ0.теплова_функція(речі)
    if _тф0.get("є"):
        for _р in речі:
            if _р.get("слот") == "верхній_шар":
                _р["тепловий_внесок"] = _тф0["тепловий_внесок"]
                if _тф0.get("тепло"):
                    _р["теплова_мітка"] = _тф0["тепло"]
                # Вісь «волога» їде тим самим кроком — її питає K-WEA-01
                # «дощовий день, а шару від дощу нема»; без мітки суддя мовчить
                if _тф0.get("волога"):
                    _р["волога_мітка"] = _тф0["волога"]
    # ── ШОВ ПЕРЕДАЄ РІВНО ТЕ, ЩО СПОЖИВАЧ ОГОЛОСИВ ───────────────────────────
    # ЩО ТУТ СТОЯЛО І ЧОМУ ЦЕ НЕ ПРАЦЮВАЛО. Відсікання ключів на `_`, дописане
    # 05.09 після того, як «руки 3/4 падали TypeError». Це був ЕКЗЕМПЛЯРНИЙ фікс:
    # він прибирав два відомі службові ключі й нічого не казав про наступний. Клас
    # повторився 07.09, щойно в нагоді зʼявились `спец` і `запити` (вхід K-ACC-07):
    # `review()` їх не приймає, і TypeError знову валив увесь суддівський шлях.
    #
    # Це третій випадок ОДНОГО класу за три дні, і жодного з них не спіймав жоден
    # гейт: `gate_e2e` і `pair_test` не викликають `перевірити_образ` узагалі.
    # Отже лікується не уважність, а сам шов: `**kw`, що їде крізь чотири шари,
    # рано чи пізно принесе ключ, якого наступний шар не оголошував.
    #
    # ВІДБІР ЗА СИГНАТУРОЮ, А НЕ ЗА СПИСКОМ ІМЕН: список імен — це той самий
    # рукописний білий список, з якого починалась уся сесія. Сигнатура ж не може
    # розійтися з функцією, бо вона і є функція. Те, що не пройшло, не зникає
    # мовчки — воно лягає в `_не_для_review` і виходить із результатом.
    # ── ПЛОЩА З ГЕОМЕТРІЇ, КОЛИ КРАЇ ВИМІРЯНІ (Н-outfit-1-081) ───────────────
    # Другий і останній вхід суду: тут образ приходить ГОТОВИМ разом із тілом, і
    # докстрінг вище вже обіцяє, що «речі несуть свої висоти (верх_см/низ_см із
    # розмірної таблиці)». Доти ця обіцянка нічого не давала колірному шару: площі
    # не було, `джерело_площі` не ставив ніхто, і пʼять колірних правил утримувались
    # навіть над образом із повністю виміряними краями. `review` тіла не приймає (і
    # не має: це шар кольору), тож шов саме тут — поруч із `_посадка`, єдиним іншим
    # споживачем геометрії на цьому рівні.
    речі, _звіт_площ = O.площі_з_геометрії(речі, тіло)
    import inspect as _inspect
    _приймає = set(_inspect.signature(_СУД.review).parameters)
    _для_review = {k: v for k, v in kw.items() if k in _приймає}
    _відсіяно = sorted(k for k in kw if k not in _приймає)
    рез = _СУД.review(F, речі, source=source, **_для_review)
    порушення = _СУД.перевірити_контракт(рез)
    вих = _СУД.для_стиліста(рез)
    if _відсіяно:
        # не мовчки: шов має право не передати ключ, але не має права про це змовчати
        вих["не_для_review"] = _відсіяно
    вих["інваріант"] = (порушення or "тримається: кожна знахідка несе неперервну силу "
                                     "з названим джерелом")
    вих["особа"] = рез["особа"]
    вих["посадка"] = посадка(тіло, речі, kw.get("intent", "conventional"),
                              _РУ_М.мета_образу(kw.get("мета", "лестити"), kw.get("мета_зони")) or "лестити",
                              тон_колготи=тон_колготи, вище="вище" in (kw.get("мета_важливо") or ()))

    # ── ШІСТЬ ПРАВИЛ, ЯКІ ІСНУВАЛИ Й НЕ БУЛИ ПІД'ЄДНАНІ ──────────────────────
    # K-PC-08, K-CRA-04, K-INT-04, K-MAT-01, K-SIL-06 (+K-SHO-02 у _посадка).
    # Правило, реалізоване й не викликане з конвеєра, не міняє жодного рішення —
    # це рівно те, у чому я щойно звинуватив корпус. Тому вони тут.
    # ── ЖОРСТКЕ «НІ» ТУТ САМЕ ТОМУ, ЩО ВОНО ВЖЕ Є В `підготувати` ────────────
    # ЗНАЙДЕНО НАСКРІЗНИМ ПРОГОНОМ: фільтр стояв ЛИШЕ у гілці обчислення вікон.
    # Композитор, що бере речі іншим шляхом (зі свого пошуку, з готового образу, з
    # історії), обходив його повністю — і образ із річчю під абсолютною забороною
    # проходив перевірку БЕЗ ЖОДНОГО СЛОВА. Абсолютний фільтр, який діє в одній
    # гілці з двох, не є абсолютним; він є звичкою.
    # Тут він не відкидає річ мовчки (образ уже зібрано — мовчазне зникнення речі
    # заплутало б), а виносить ГЕЙТ: видно, що саме порушено й чому.
    зн_ні = []
    if жорстке_ні:
        _, відкинуті = PR.жорстке_ні_фільтр(речі, жорстке_ні)
        for в in відкинуті:
            зн_ні.append(dict(_РЕЄСТР.зн(
                "профіль", "hard",
                "«%s» під жорстким «ні»" % (в.get("назва") or в.get("id")),
                [в.get("назва") or в.get("id")],
                "збіг із «%s» — це особиста межа, названа людиною. Обґрунтування не "
                "потрібне, і система не пропонує спробувати (тема-6 PART 12)"
                % в.get("через"),
                ремонт=["інша річ у цьому слоті"],
                заяви=[_ВМ.заява("item_under_her_hard_no")],
                ремонт_заяви=[_ВМ.заява("other_item_in_slot")]),
                # `регістр="гейт", блокує=True` поверх `_зн` знято Н-02-05 разом із
                # трьома іншими механізмами регістру: гейт видає `регістр()` з єдиної
                # таблиці — `ПОЛІТИКА_РЕГІСТРУ["профіль"]`, підстава `МЕЖА_ЛЮДИНИ`.
                # Ключ таблиці тут не код правила, а те, що стоїть у полі `правило`
                # цієї знахідки: жорстке «ні» — це межа людини, а не правило корпусу.
                сила_нп=1.0,
                сила_нп_джерело="межу встановила людина, не вимір",
                # ── K-PER-05 НАЗИВАЄ СЕБЕ НА ЦІЙ ЗНАХІДЦІ (друге проходження) ──
                # `правило` тут лишається «профіль», і це НЕ описка: ключ
                # `ПОЛІТИКА_РЕГІСТРУ` береться саме з цього поля, а жорстке «ні» —
                # межа ЛЮДИНИ, не правило корпусу (абзац вище). Але корпус має для
                # цієї межі власний код — K-PER-05, сила `hard` «on the person's
                # authority alone», з двома дослівними прикладами («will not wear
                # wool against skin, will not wear heels»), — і доти він не стояв у
                # виході ніде. Поле `також_правила` — рівно той механізм, яким
                # система вже вимовляє «цей рядок є ще й тим правилом»
                # (K-SIL-04/07 на K-COL-01, K-KOH-04 на K-REG-01): ID доїжджає до
                # вердикту, а таблиця регістру лишається недоторканою.
                також_правила=["K-PER-05"]))

    # ── ТА САМА СЦЕНА, ЩО В СУДДІ (K-COND-04) ───────────────────────────────
    # `review` виводить відстань огляду сам і судить на ній; цей E збирається
    # ОКРЕМО і йде в крок редагування та в чеклісти. Без цього рядка вони
    # рахували б той самий образ на іншій вазі, а пункт 19 чекліста надлишку
    # («вага приобличчевих слотів ключована на відстань огляду») стояв би «без
    # входу» навіть тоді, коли нагода відстань назвала.
    _дист_образу = _ДИСТ.з_сценарію(dict(місце=kw.get("місце"), формат=kw.get("формат"),
                                          нагода=kw.get("нагода"))).get("дистанція")
    E = O.елементи(речі, дистанція=_дист_образу)

    # K-PC-08 стоїть ПЕРШИМ і окремо: це абсолютний фільтр, і решта правил не має
    # права рахувати образ, у якому лишилась річ під вето. Порядок значущий.
    E_чисті, вето_зн = _СУД.вето_покриття(E, вето=вето_покриття, тіло=тіло)
    # `E_чисті` — це стан «у_приміщенні» (`елементи()` за замовчуванням), і стан
    # тепер їде далі: інакше BREAKS правила K-MAT-03 діяв у судді й не діяв у
    # кроці редагування, тобто одне правило давало дві різні відповіді.
    # НАМІР ЇДЕ В КРОК: підлога, нижче якої K-CRA-04 не ріже, — та сама, що в
    # `підлога_інтересу_проактивно` нижче, а не стала 1.
    _намір_кроку = kw.get("intent", "conventional")
    # СЦЕНА — ТА САМА, ЩО В СУДДІ: без неї `формальність_образу` в метриках кроку не
    # бачила ні коду, ні нагоди, і K-KOH-05 (смуга, «мусить бути сукня») у «стало гірше» не входив —
    # зняття сукні чи жакета за кодом не мірялось.
    _сцен_кроку = рез.get("сценарій") if isinstance(рез, dict) else None
    зайві, підлога, метрики = _СУД.крок_редагування(E_чисті, темп_c=kw.get("темп_c"), опади=kw.get("опади"), вітер=kw.get("вітер"), речі=речі, стан="у_приміщенні", intent=_намір_кроку,
                                                    сцен=_сцен_кроку)
    # ВЕРХНІЙ ШАР ІСНУЄ ЛИШЕ НАДВОРІ (K-WEA-02): `елементи()` за замовчуванням дає стан
    # «у_приміщенні» — без пальта. Тож `верхній_шар` у ЗНІМНІ_СЛОТИ був мертвий на живому
    # шляху: крок редагування ніколи не бачив пальта (виміряно 28.08: K-CRA-04 на
    # верхньому шарі 0/200 у холодній сцені з пальтом). Тепер образ із пальтом
    # редагується і в стані «надворі», з температурою: у спеку пальто — «можна зняти»,
    # у холод його видалення робить K-WEA-01 гіршим, і крок мовчить.
    E_над = None        # стан «надворі» є лише з верхнім шаром; його читає й вхід пункту 5 чекліста
    if any(r.get("слот") == "верхній_шар" for r in речі):
        E_над, _ = _СУД.вето_покриття(O.елементи(речі, стан="надворі", дистанція=_дист_образу),
                                      вето=вето_покриття, тіло=тіло)
        # Кандидат «без шару» — `E_чисті`: без пальта видно сукню чи верх, які воно ховало.
        з2, п2, _ = _СУД.крок_редагування(E_над, темп_c=kw.get("темп_c"), опади=kw.get("опади"), вітер=kw.get("вітер"), речі=речі,
                                         intent=_намір_кроку, E_без_шару=E_чисті, сцен=_сцен_кроку)
        _є = {(z["правило"], tuple(z.get("речі") or ())) for z in list(зайві) + list(підлога)}
        зайві = list(зайві) + [dict(z, стан="надворі") for z in з2 if (z["правило"], tuple(z.get("речі") or ())) not in _є]
        підлога = list(підлога) + [dict(z, стан="надворі") for z in п2 if (z["правило"], tuple(z.get("речі") or ())) not in _є]
    # K-INT-04 проактивно — на ЗІБРАНОМУ образі, не лише під час вибору.
    # Пул у траурному регістрі (мітка `траур_пулу`, яку шов кладе лише
    # рукам 1–2, і стан не скінчився) — ремонт підлоги лише фактурою.
    _тихо = bool(((kw.get("траур_пулу") or {}).get("випадок") or {}).get("лишилось"))
    підлога = list(підлога) + _СУД.підлога_інтересу_проактивно(E_чисті, kw.get("intent", "conventional"),
                                                                 тихо=_тихо)
    вих["композиція"] = dict(
        жорстке_ні=зн_ні,
        вето_покриття=вето_зн,
        покриття_без_поля=_СУД.покриття_без_поля(E, тіло=тіло),
        відкриті_зони=sorted(O.відкриті_зони_образу(E_чисті, тіло=тіло)[0]),
        крок_редагування=зайві,
        підлога_інтересу=підлога,
        джерела_інтересу=_СУД.джерела_інтересу(E_чисті),
        метрики=метрики,
        тканина_проти_крою=_СУД.тканина_проти_крою(E_чисті),
        масштаби=_СУД.масштаби(E_чисті, тіло=тіло),
        порядок="K-PC-08 (вето) → K-CRA-04×K-INT-04 (редагування) → K-MAT-01 → K-SIL-06. "
                "Вето перше навмисно: решта не має рахувати образ із річчю під вето")

    # ── АКСЕСУАРНА ГІЛКА (тема-10) ───────────────────────────────────────────
    # ЩО ЦЕ МІНЯЄ (правило 3). Модуль, написаний і не викликаний із конвеєра, не міняє
    # жодного рішення — це рівно той дефект, який система вже ловить у корпусі. Тому
    # виклик стоїть ТУТ, а не «десь потім»; і ворота стоять ОКРЕМИМ ключем від
    # преференцій, бо це різні дії: ворота відкидають, преференції впорядковують.
    # Порядок значущий і взятий із теми (ЧАСТИНА XXVII): сезон/температура → розмір →
    # матеріал×погода → підошва, і лише потім усе, що про вигляд.
    # ── ГІЛКА ВЕРХНЬОГО ШАРУ (тема-11) ───────────────────────────────────────
    # ЩО ЦЕ МІНЯЄ (правило 3). Верхній шар доти був СЛОТОМ і нічим більше: він
    # рахувався в K-WEA-01 штукою і займав поле в K-WEA-02. Тепер він має стан,
    # теплову функцію з трьох осей, геометрію країв і власні ворота.
    # ПОРЯДОК ЗНАЧУЩИЙ: `теплова_функція` рахується ДО `суд_образу.review`, бо її число
    # входить у лічбу шарів — інакше K-WEA-01 порахував би тренч штукою, а
    # виправлення приїхало б після того, як знахідка вже вийшла.
    _вш = _ВШ0.перевірити(
        речі, тіло=тіло, темп_c=kw.get("темп_c"), вітер=kw.get("вітер"),
        опади=kw.get("опади"), реагенти=реагенти,
        тривалість_год=тривалість_год, гардероб=гардероб)
    вих["верхній_шар"] = _вш

    # `спец`/`запити` — вхід для K-ACC-07: без них правило, яке ЄДИНЕ в темі-10
    # розширює каталог, кликалось лише з тестів і не міняло жодного рішення.
    _акс = АК.перевірити(
        тіло, речі, темп_c=kw.get("темп_c"), опади=kw.get("опади"),
        реагенти=реагенти, тривалість_год=тривалість_год,
        поверхня=поверхня, гардероб=гардероб,
        # `особа` — вхід K-SHO-04/08: L* шкіри як сусідньої поверхні для краю
        # взуття. Береться той самий запис, що вже стоїть у `вих["особа"]`, а не
        # `спец`: на шляху `від_моделі` рис у специфікації нема (виміряно 17.09).
        спец=kw.get("спец"), запити=kw.get("запити"), особа=рез.get("особа"),
        # «Мороз» без градусів — заява відчуттям, число коду лишається порогам
        відчуття=kw.get("погода_відчуття") if kw.get("темп_з_відчуття") else None)
    _акс["надточний_збіг"] = АК.надточний_збіг(
        E_чисті, заявлена_колона=bool(заявлена_колона))
    # ВХІД ПУНКТУ A12 (K-ACC-10) — З ТИХ САМИХ ЕЛЕМЕНТІВ, ЩО Й ПРАВИЛО.
    # `входи_чекліста` гілки рахує з РЕЧЕЙ, а акцентна поверхня — властивість
    # елемента кольору (`нейтраль` рахується з lab елемента), тож цей вхід
    # дописується тут, де `E_чисті` уже є, одним відбором із правилом.
    if isinstance(_акс.get("входи_чекліста"), dict):
        _акц = len({e.get("слот") for e in АК.акцентні_поверхні(E_чисті)})
        _акс["входи_чекліста"]["≥2 акцентні поверхні"] = _акц >= 2
        _виміряний = _СУД.колір_виміряний
        if _акц < 2 and all(_виміряний(e) for e in E_чисті):      # Колір слова — не вимір: другої акцентної поверхні нема — пункт A12 не стосується
            _акс["входи_чекліста"].setdefault("не_стосується", {})["≥2 акцентні поверхні"] = (
                "object_absent:" + ("акцент" if not _акц else "другий_акцент"))
        # ВХІД ПУНКТУ A13 (K-WEA-01/05) — погода нагоди: вона є тут, у
        # `kw`, а не в речах, з яких рахує `входи_чекліста`
        _акс["входи_чекліста"]["погода дня"] = (kw.get("темп_c") is not None
                                                or kw.get("опади") not in (None, ""))
    _акс["віднімання"] = АК.віднімання(E_чисті)
    # ПОРАДА — НЕ ЗНАХІДКА, КОЛИ ВАДИ НЕМА (ФОКУС-1). K-ACC-06 «річ можна
    # носити несиметрично» — четверте джерело інтересу саме для образу, що не дотягує до
    # підлоги K-INT-04 (корпус: «a wholly neutral outfit can meet the floor with no colour
    # at all»). На образі, де підлогу вже набрано, вона стояла знахідкою з силою 0,5 на
    # 577 ідеях розбору 02.10 і з'їдала ремонт. Там вона лишається опцією каналу 3
    # (`МІСЦЕ_НАСЛІДКИ`) і слідом, а знахідкою — лише поруч зі справжнім браком інтересу.
    if not _СУД.підлога_інтересу_проактивно(E_чисті, kw.get("intent", "conventional")):
        _акс["преференції"] = [z for z in (_акс.get("преференції") or [])
                               if z.get("правило") != "K-ACC-06"]
    вих["аксесуари"] = _акс

    # ── СІМ'Я РЕМЕСЛА (тема-4 ЧАСТИНА X): K-CRA-01/02/03/06/10 + K-CRA-12 ────
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ. Шість правил ремесла судять ЗІБРАНИЙ образ цілком —
    # скільки в ньому речей, фокусів, шарів, жестів і якого формату хустка, — і
    # такого місця в суді не було: `review` ходить по СТАНАХ і по кольору, а
    # `brief` лише лишав слід у лог. Тому виклик стоїть ТУТ, поруч із кроком
    # редагування, і після гілок тем 10 і 11: K-CRA-03 годується КОМАНДАМИ
    # розкладки верхнього шару (K-CRA-11: «образ — це набір речей плюс набір
    # команд»), тож гілка мусить бути порахована раніше. Порядок значущий.
    _команди_образу = (list((_вш or {}).get("команди") or [])
                       + list((_вш or {}).get("ремонти") or []))
    # ФОКУС-1: K-CRA-02 читає ролі слотів схеми (`спец`) — акцент схеми лишається, решта
    # фокусів стишується (`суд_ремесло.групи_фокусів`). Фокусної зони сценарій не несе
    # (поле нагоди `фокус` не оголошене), тож її тут не читається
    вих["ремесло"] = (_СУД.ремесло(речі, E_чисті, _команди_образу,
                                   kw.get("intent", "conventional"), спец=kw.get("спец"))
                      + АК.формат_хустки(речі))

    # ── СИЛУЕТ ЗІБРАНОГО ОБРАЗУ (тема-4 PART V): K-SIL-09 + K-SIL-10 ─────────
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ. Обидва правила судять ОБРАЗ, і жодне не мало місця:
    # `_посадка` рахує силует по ГЕОМЕТРІЇ ТІЛА (їй потрібні виміряні краї, яких
    # фід не дає), `review` — по станах і кольору, і саме там K-SIL-09 жило за
    # гейтом площ. Тут воно судиться за СЛОТАМИ — рівно так, як його формулює
    # корпус, — а K-SIL-10 дістає першого емітента. Відро окреме від `ремесло`,
    # бо це інша сім'я; шов до вердикту в них один.
    вих["силует_образу"] = _СУД.силует_образу(речі, E_чисті,
                                              kw.get("intent", "conventional"))

    # ── ШАР РЕЄСТРІВ (тема-13) ────────────────────────────────────────────────
    # Тема-13 була відсутня в коді ЦІЛКОМ — 20+ правил K-REG, при тому що вхід під
    # них у фіді є (тип 100 %, крій, принт, матеріал, колір). Реєстр — ОКРЕМА вісь
    # від формальності: рівень 5 існує і в класиці, і в стритвер, і в бохо.
    # Знахідки не блокують: словники маркерів на фіді не перевірені, і тема сама
    # так їх позначає.
    _зн_реєстрів, _реєстр = _РЕ.перевірити(
        речі, _РЕЄСТР.зн,
        реєстр_людини=kw.get("реєстр_людини"),
        сцен=рез.get("сценарій") if isinstance(рез, dict) else None,
        заявлений_злам=bool(kw.get("заявлений_злам")))
    вих["реєстри"] = dict(знахідки=_зн_реєстрів, вектор=_реєстр.get("вектор"),
                          домінанта=_реєстр.get("домінанта"),
                          цитати=_реєстр.get("цитати"),
                          словами=_РЕ.словами(_реєстр))

    # ── МОВНИЙ ГЕЙТ НА ВЛАСНОМУ ВИХОДІ ───────────────────────────────────────
    # Дванадцять анти-правил корпусу — hard, і всі про те, що система має право
    # СКАЗАТИ. Найімовірніше місце появи забороненої формули — не вільний текст ШІ,
    # а `ремонт` НАШИХ правил: саме там система радить, що робити з тілом.
    # ── ЗБИРАЄТЬСЯ ОБХОДОМ, А НЕ ПЕРЕЛІКОМ ВІДЕР ─────────────────────────────
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after, виміряно на `каталог_повний`).
    #   before — тут стояв перелік із сімнадцяти імен відер. `accessory.перевірити`
    #            віддає шість відер знахідок; перелік брав чотири. Поза ним
    #            лишались `питання`, `без_відповіді` і `канал_3`. Наслідки:
    #            (а) блок припущень нижче будується циклом по цьому списку, тож
    #                аксесуарне «входу нема» не потрапляло в припущення ЖОДНОГО
    #                разу — а K-IO-03 має силу `hard`;
    #            (б) `канал_3` (команди розкладки, K-CRA-11 / K-CHN-01) не читав
    #                НІХТО в усьому дереві: третій канал виходу генерувався і
    #                викидався;
    #            (в) мовний гейт не бачив текстів цих знахідок, тобто дванадцять
    #                анти-правил корпусу на них не діяли.
    #   after  — обхід за ФОРМОЮ знахідки. Нове відро включається само; забути
    #            дописати його нікуди.
    # ЦІНА, І ВОНА НАЗВАНА: обхід бачить і те, що лежить у виході двічі (знахідка
    # законно буває у `ворота` і в `преференції`), тому дублікати знімаються за
    # ключем «правило + суть + речі» — тим самим рядком, який побачить людина.
    # МЕЖА ЦІЄЇ ОБІЦЯНКИ, НАЗВАНА ПРЯМО. Ключ несе
    # ПРАВИЛО, тож він знімає лише те саме правило з тим самим текстом. Дубль із
    # РІЗНИМИ кодами, порахований з ОДНОГО виміру, тут не ловився й не міг: саме
    # так K-SIL-01 (`без_літери`) і K-SIL-03 (`об_єм`) їхали в бриф двома реченнями
    # з одного числа, поки їх не злили на емітенті (silhouette._форма_не_читається).
    # Вивід: дубль кодів лікується там, де знахідка НАРОДЖУЄТЬСЯ, а не тут — труба
    # не знає, що два коди міряють одне, і знати не може.
    _пари = ЗН.без_повторів(
        ЗН.усі(dict(гілки=[зн_ні, вето_зн, зайві, підлога],
                    композиція=вих.get("композиція"),
                    посадка=вих.get("посадка"),
                    аксесуари=_акс,
                    верхній_шар=_вш,
                    # без цього рядка пункти 2, 8 і 10 чекліста надлишку лишались
                    # би «пройдено» при наявній знахідці: провал ставить лише
                    # знахідка, а чекліст читає РІВНО цей обхід
                    ремесло=вих.get("ремесло"),
                    # те саме, що рядком вище: пункт 4 чекліста надлишку читає
                    # РІВНО цей обхід, і без нього K-SIL-09/K-SIL-10 не могли б
                    # ані провалити пункт, ані пройти мовний гейт
                    силует_образу=вих.get("силует_образу"),
                    # ── ШАР РЕЄСТРІВ ТЕЖ ЗБИРАЄТЬСЯ ───────────────────────────
                    # Його тут не було, і наслідок був той самий, що в коментарі
                    # вище про `accessory`: знахідки теми-13 (K-REG-01/05/06…) не
                    # входили ні в мовний гейт, ні в чеклісти, ні в блок
                    # припущень — тобто пункт 13 чекліста надлишку не міг
                    # провалитись НАВІТЬ тоді, коли K-REG-01 стояв у вердикті.
                    # Обхід іде за ФОРМОЮ, тож `вектор`, `домінанта` й `словами`
                    # у збір не потраплять — вони знахідками не виглядають.
                    реєстри=вих.get("реєстри"),
                    стани=рез.get("стани"))))
    _усі_зн = [з for _, з in _пари]
    вих["мовний_гейт"] = МГ.перевірити_знахідки(_усі_зн)
    # ── K-IO-04 СХЕМА ВИХОДУ: чекліст надлишку → чекліст прісності → припущення ──
    # (тема-4 XIV.2). K-IO-03: кожне припущення — явно в блоці, не мовчки в числах.
    # ── ТРЕТІЙ ЧЕКЛІСТ — ПРАКТИКОВА ПАЛІТРА (K-PAL) ──────────────────────────
    # Входи рахуються з `F` тут, а не беруться з специфікації: `перевірити_образ`
    # кличеться на КОЖНІЙ комбінації композитора, і повна `палітра_практична`
    # (кольори, назви, трійки) на кожній із них коштувала б за те, чого чекліст не
    # питає. `входи_палітри` бере лише осі й три вікна — та сама арифметика, що
    # вже стоїть у `композитор_оцінка.оцінити` під K-PAL-16.
    # ── ЧЕТВЕРТИЙ ЧЕКЛІСТ — АКСЕСУАРИ (тема-10) ──────────────────────────────
    # Входи бере з гілки, що вже порахована вище: вона тримає і речі, і таблиці,
    # і тривалість нагоди. Дев'ять правил теми-10 доти мовчали на живому шляху, і
    # мовчання «нема входу» було невідрізненне від «перевірено, чисто».
    # ── І ВЕКТОР РЕЄСТРІВ (K-KOH-04) ────────────────────────────────────────
    # Пункт 13 («жанр має домінанту») доти питав поле `жанр`, якого не пише ніхто,
    # і стояв «без входу» на кожному образі. Справжній вхід — той самий вектор,
    # що вже порахований двадцятьма рядками вище; передати його коштує аргументу.
    _місце_ба = kw.get("місце")
    вих["чеклісти"] = _СУД.чеклісти(_усі_зн, E_чисті, kw.get("intent", "conventional"),
                                    палітра=_СУД.входи_палітри(F, source, kw.get("самозвіт"),
                                                               вибір_схеми=kw.get("вибір_схеми")),
                                    реєстр=(_реєстр or {}).get("вектор"),
                                    аксесуари=_акс.get("входи_чекліста"),
                                    розмова=kw.get("розмова_шаром"),
                                    # Нагода без акценту: траурний пул чи служба в церкві
                                    без_акценту=("траур" if _тихо else
                                                 _місце_ба if _місце_ба in _ПЛ_ба.НАГОДИ_БЕЗ_АКЦЕНТУ
                                                 else None),
                                    E_надворі=E_над)
    _припущ = []
    for _з in _усі_зн:
        if isinstance(_з, dict) and _з.get("сила") in ("питання", "утримано"):
            # БЕЗ СТЕЛІ 90 ЗНАКІВ: `припущення` читає рівно звіт
            # власника (`етапи.суд.припущення`), і обрізане на півслові «код
            # припустив ось що» — це припущення без його умови.
            _припущ.append(dict(правило=_з.get("правило"), що=str(_з.get("суть", ""))))
    for _р in речі:
        if _р.get("край_джерело") == "дефолт слота":
            _припущ.append(dict(правило="K-CUT-00", що="край «%s» узято з дефолту слота (довжини у фіді нема)" % (_р.get("id"))))
        elif _р.get("край_джерело") == "слово":
            # K-IO-03: рівень зі слова каталогу — теж припущення, лише вужче за дефолт
            _припущ.append(dict(правило="K-FIT-03", що="край «%s» — рівень «%s» зі слова каталогу, ±%s см"
                                % (_р.get("id"), _р.get("довжина_рівень"), _р.get("край_розкид_см"))))
    вих["припущення"] = _припущ
    # Застава тут не потрібна: `_СЛ` — `trace`, модуль ядра, імпортований
    # тут же без застави; `запис` тотальний. Ковталась помилка коду в підстановці
    # (зокрема `вих["чеклісти"]["підсумок"]["надлишок"]` — KeyError, якщо чеклісти
    # не зібрались), і вона мовчки лишала лог без K-IO-04/K-IO-03. Тепер летить у
    # `bridge.виклик` → `помилка` + `код`, і показ показує рядок жінці.
    _СЛ_IO.запис("K-IO-04", "output_scheme_findings_checklists_assumptions", "перевірити_образ",
              значення="припущень %d; надлишок %s" % (len(_припущ), вих["чеклісти"]["підсумок"]["надлишок"]),
              сила=None, напрям="контракт виходу")
    if _припущ:
        _СЛ_IO.запис("K-IO-03", "assumptions_made_explicit", "перевірити_образ",
                  значення="%d" % len(_припущ), сила=None, напрям="робастний фолбек")
    # ── СЛІД ДРУГОЇ ПОЛОВИНИ КОНВЕЄРА ────────────────────────────────────────
    # ЩО ЦЕ МІНЯЄ (правило 3). Знахідки ТУТ уже несли поле `правило` — і саме
    # тому гейт досяжності оголошував їх мертвими: його батарея викликала лише
    # `палітри`/`запити`, тобто половину труби ДО вибору речей. Усе, що вміє
    # спрацювати лише на ЗІБРАНОМУ образі (K-FIT-*, K-BOD-*, K-CLR-05 на металі,
    # K-MAT-*, K-KOH-03/10), у нього фізично не мало шансу з'явитись. Правило,
    # оголошене мертвим гейтом, який його не викликав, — хибний позитив, і він
    # коштував дорожче за мовчання: за таким списком лікували б не те.
    for _з in _усі_зн:
        if isinstance(_з, dict) and _з.get("правило"):
            # ЯРЛИК І ЗНАЧЕННЯ ЦІЛІ: слід правил їде у звіт власника
            # полем `етапи.прогін.слід_правил`, і саме `значення` входить у ключ
            # дедуплікації `trace.зібрати`. Зі стелею 80 знаків дві різні
            # знахідки одного правила, що збігались першими вісімдесятьма
            # символами, зливались в одну зі «спрацювань 2» — тобто стеля
            # тексту мовчки міняла ЛІЧБУ, а не лише вигляд рядка.
            _СЛ_IO.запис(_з["правило"], "finding_fired", "перевірити_образ",
                      значення=str(_з.get("суть", "")),
                      сила=_з.get("сила_нп"), напрям=_з.get("регістр"))
    return вих


def посадка(тіло, речі, intent, мета, тон_колготи=None, вище=False):
    """Посадка й силует образу на тілі (fit + silhouette по речах із краями в см):
    повертає dict(проганялось, знахідки, вимір, силует) або dict(проганялось=False, чому)."""
    if тіло is None:
        return dict(проганялось=False,
                    чому="не передано тіло (посадка.тіло(зріст, обхвати)) — геометрія "
                         "речі нема з чим порівнюватись",
                    наслідок="P0-шар рулбука мовчить: образ може пройти за кольором і "
                             "не сидіти")
    гео = [р for р in речі if O.довжина_відома(р)]
    якщо_нема = [р["id"] for р in речі if р not in гео]
    if not гео:
        return dict(проганялось=False,
                    чому="жодна річ не несе верх_см/низ_см — це числа з розмірної "
                         "таблиці магазину, і без них посадка не міряється",
                    наслідок="P0-шар мовчить")
    # СИЛУЕТ ДІСТАЄ ПОВНИЙ СПИСОК, ПОСАДКА — `гео`. `fit`
    # міряє КРАЙ кожної речі й без сантиметрів міряти нема чого; силует же будує
    # КОНТУР образу — річ без довжини з нього випадає, але мовчки випадати не має
    # права: `силует_суд.довжини_відомі` називає її знахідкою K-FIT-03 «питання».
    # Доти вона стояла лише в полі `без_геометрії` нижче, якого не читає ніхто.
    зв_с = СЛ.звіт(тіло, речі, intent)
    return dict(проганялось=True, без_геометрії=якщо_нема or None,
                знахідки=(ПС.перевірити(тіло, гео, intent=intent, мета=мета, вище=вище,
                                          # верхній шар/верх без довжини відсіяно в `гео`; K-SIL-02
                                          # має знати, що їхній поділ невідомий (ФІГ-600)
                                          без_довжини=[р["id"] for р in речі if р not in гео
                                                       and р.get("слот") in ("верх", "верхній_шар")])
                          + СЛ.перевірити(тіло, речі, intent=intent, мета=мета)
                          # K-SHO-02: смуга шкіри між халявою й поділом. Міряє
                          # інтервал МІЖ двома краями — того, чого K-FIT-03 не бачить,
                          # бо дивиться на кожен край окремо.
                          + ПС.смуга_шкіри(тіло, гео, тон_колготи=тон_колготи)),
                вимір=ПС.звіт(тіло, гео, intent, мета)["тіло"],
                силует=dict(літера=зв_с["літера"], під_тіло=зв_с["під_тіло"],
                            якорі=зв_с["якорі"], площа=зв_с["площа"],
                            обгортка=[(з["рівень"], з["ширина_тіла"], з["припуск"],
                                       з["ширина"], з["носій"]) for з in зв_с["обгортка"]
                                      if з["одягнено"]]))
