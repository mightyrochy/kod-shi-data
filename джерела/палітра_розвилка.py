"""РОЗВИЛКА: колорит особи → РОЗПОДІЛ законних схем (кілька гілок з вагою згоди), не
одна. `розвилка` ключує на value-контрасті (є завжди) з частками належності до блоків
(людина — зона), несе провенанс кожної гілки (`_провенанс_гілки` з
ПРОВЕНАНС_РОЗВИЛКИ через `_ПРОВЕНАНС_ЗА_СХЕМОЮ`), ранг надійності K-COL-03 і слід
у `trace`, застереження R-MUA-04 (яскравий макіяж уже тримає фокус), під statement
— гілки-мисматчі.

ЧОМУ ОКРЕМИЙ ФАЙЛ (20.09.2026, хвиля стандарту, СТАНДАРТ_КОДУ п.16: файл
≤ 1 500 рядків). `palette.py` виріс до 2 746 рядків; тіло розділено на вісім модулів
`палітра_*` ЧИСТИМ перенесенням, а `palette` лишився фасадом із реекспортом кожного
імені. Розвилка читає таблиці схем і ваг із `палітра_схеми` і більше нічого з
палітри: вона — перший крок «особа → палітра», а специфікація й запити стоять вище
по течії. Читає її `палітра_специфікація` (`розвилка_специфікацій` проганяє кожну
гілку через `специфікація`).

ЩО ТУТ (рядки — за `palette.py` до поділу, коміт efa403e): _ПРОВЕНАНС_ЗА_СХЕМОЮ,
`_провенанс_гілки`, `розвилка` (534–683). `face_contrast` і `trace` імпортуються
ліниво в тілі `розвилка`, як і було.

РЕБРА. `палітра_схеми` і зовнішнє (`реєстр_правил`); не фасад."""
import реєстр_правил as _РЕЄСТР
from палітра_схеми import (СХЕМИ, _РАНГ_K_COL_03, ТІЛЬКИ_STATEMENT, _ПОРЯДОК_ВАГ, _ВАГА_НП,
    частки_блоків, _вага_словами, ПРОВЕНАНС_РОЗВИЛКИ, РОЗВИЛКА_ЗГОДИ, ПРОПОРЦІЯ, пропорція)


# Мапа гілка -> записи ПРОВЕНАНС_РОЗВИЛКИ, які під нею стоять. Зв'язок, якого доти
# не існувало: словник провенансу лежав поруч зі словником гілок і ніде не зустрічався.
_ПРОВЕНАНС_ЗА_СХЕМОЮ = {
 "нейтрали+акцент": ("нейтральна_база", "контраст_образу∝контраст_особи"),
 "тональна":        ("тональна↔аналогова_межа", "контраст_образу∝контраст_особи"),
 "аналогова":       ("тональна↔аналогова_межа", "контраст_образу∝контраст_особи"),
 "приглушена_комплементарна": ("комплемент_як_акцент", "ясність→хрома_акценту"),
 "тріада":          ("тріада_не_щоденна",),
 "контраст-мисматч": ("контраст_образу∝контраст_особи",),
}

def _провенанс_гілки(схема):
    """Родовід гілки з ПРОВЕНАНС_РОЗВИЛКИ у машиночитному вигляді."""
    ключі = [k for k in _ПРОВЕНАНС_ЗА_СХЕМОЮ.get(схема, ()) if k in ПРОВЕНАНС_РОЗВИЛКИ]
    if not ключі:
        return dict(тір="T3", однородовідно=None, згода="не записана",
                    родовід="—", калібр="—",
                    застереження="провенанс цієї гілки не записаний — читати як T3 без родоводу")
    зап = [ПРОВЕНАНС_РОЗВИЛКИ[k] for k in ключі]
    згоди = " | ".join(з["згода"] for з in зап)
    одно = any("ОДНОродовідна" in з["згода"] or "R-TYP-02" in з["родовід"]
               or "PCA" in з["родовід"] for з in зап)
    return dict(тір=min((з["t"] for з in зап), key=lambda t: -int(t[1])),
                однородовідно=одно, згода=згоди,
                родовід=" | ".join(з["родовід"] for з in зап),
                калібр=" | ".join(з["калібр"] for з in зап),
                застереження=("широка згода тут НЕ є незалежним сходженням: джерела "
                              "з одного PCA-дерева (R-TYP-02) — це один голос, повторений"
                              if одно else "родовід міжлінійний"))

def розвилка(особа, intent="conventional"):
    """Колорит особи -> РОЗПОДІЛ законних схем (кілька гілок з вагою згоди), НЕ одна.
    Ключує САМЕ на тому, що реально доступно: value-контраст (є завжди) — головний ключ;
    ясність (colour_contrast) — лише м'який модифікатор і лише коли K-PC-05 її пустив.

    Повертає не «правильну» схему, а розвилку: гілки, впорядковані за порядковою вагою,
    вісь розходження (де на цьому вході практика законно розходиться) і чесний перелік,
    де згоди нема. Під statement-інтентом додаються гілки, які під conventional вважались
    би промахом (тріада; свідомий контраст-мисматч) — бо там мета інша, ніж лестити обличчю."""
    рівень = особа.get("рівень")
    if рівень not in РОЗВИЛКА_ЗГОДИ:
        raise ValueError(f"нема рівня контрасту в профілі особи (рівень={рівень!r})")
    conv = _РЕЄСТР.стриманий_намір(intent)   # K-PER-00: comfort_first / context_optimal — теж конвенція
    # людина — зона: частки належності до блоків за value-gap; блок мітки — домінантний
    # (мітка з outfit.рівень_контрасту лишається розв'язком нічиєї рівно на порозі)
    частки = частки_блоків(особа.get("value_gap")) or {рівень: 1.0}
    домінантний = max(частки, key=lambda k: (частки[k], k == рівень))
    блок = РОЗВИЛКА_ЗГОДИ[домінантний]
    сусід = next((k for k in sorted(частки, key=частки.get, reverse=True) if k != домінантний and частки[k] >= 0.25), None)
    ясність = особа.get("colour_contrast")   # None, якщо K-PC-05 загейтував
    import face_contrast as _KC
    _яскравий_мк = _KC.рівень_макіяжу(особа.get("макіяж")) == "яскравий"

    гілки = []
    for і_блоку, (схема, вага, коли, застереження) in enumerate(блок["гілки"]):
        if схема in ТІЛЬКИ_STATEMENT:        # (у РОЗВИЛКА_ЗГОДИ їх і так нема, але страхуємось)
            continue
        # вага = сума ваг схеми в усіх блоках, зважена частками (0, якщо блок її не має)
        нп = sum(ч * _ВАГА_НП.get(next((в for с, в, *_ in РОЗВИЛКА_ЗГОДИ[б]["гілки"] if с == схема), None), 0.0)
                 for б, ч in частки.items())
        g = dict(схема=схема, вага=_вага_словами(нп), вага_нп=round(нп, 3), коли=коли, застереження=застереження,
                 _порядок_блоку=і_блоку)
        if сусід:
            в_сусіда = next((в for с, в, *_ in РОЗВИЛКА_ЗГОДИ[сусід]["гілки"] if с == схема), None)
            if в_сусіда and в_сусіда != вага:
                g["на_межі_з"] = "%s (частка %.0f %%): там ця гілка — «%s»" % (сусід, 100 * частки[сусід], в_сусіда)
        g["пропорція"] = пропорція(схема, домінантний, intent)
        # ПРОВЕНАНС ТЕПЕР ВИРІШУЄ, а не лежить: гілка несе свій родовід, і однородовідна
        # згода (усе з PCA-дерева Color Me Beautiful, R-TYP-02) ПОЗНАЧАЄТЬСЯ — щоб
        # стиліст не читав «багато джерел» як незалежне підтвердження. Доти цей словник
        # був 66 рядків прози, які ніхто не читав ні очима, ні кодом.
        g["провенанс"] = _провенанс_гілки(схема)
        # м'який модифікатор ясності — тільки для акцентних/комплементарних гілок і тільки коли є
        if ясність is not None and схема in ("приглушена_комплементарна", "нейтрали+акцент"):
            if ясність >= 0.45:
                g["хрома_акценту"] = "ясність особи дозволяє чистіший акцент (проксі rel_C рис)"
            elif ясність <= 0.30:
                g["хрома_акценту"] = "приглушений колорит: акцент тримати приглушеним"
        # ── R-MUA-04: БЮДЖЕТ ІНТЕРЕСУ ЙДЕ ЧЕРЕЗ ОБЛИЧЧЯ (19.09.2026) ────────
        # Корпус: «one loud feature; the rest supported, not amplified» — макіяж є
        # важелем на боці ЛЮДИНИ в тому самому бюджеті інтересу, що й одяг
        # (тема-6 §3.5). Прямого правила про ВАГИ схем корпус не дає, тож ваги
        # гілок не чіпаються: яскравий макіяж лише позначається на акцентних
        # гілках як застереження (пояснення жінці й моделі), і рядок фокусу в
        # брифі несе те саме. Переважити гілку — було б тихою зміною ваг без
        # входу з корпусу; це сказано тут, а не зроблено мовчки.
        if _яскравий_мк and схема in ("приглушена_комплементарна", "нейтрали+акцент"):
            g["фокус_макіяжу"] = ("яскравий макіяж уже тримає фокус на обличчі — акцент "
                                  "одягу приглушений, вага гілки не змінена (R-MUA-04)")
            g["застереження"] = ((g.get("застереження") or "").rstrip(". ") + ". " if g.get("застереження") else "") + \
                "Яскравий макіяж уже тримає фокус на обличчі: акцент одягу — приглушений (R-MUA-04)."
        # ── K-COL-03: РАНГ НАДІЙНОСТІ ЇДЕ РАЗОМ ІЗ ГІЛКОЮ ──────────────────
        # ЩО ЦЕ МІНЯЄ (правило 3). before: `СХЕМИ` впорядковані за спаданням
        # надійності рівно так, як каже K-COL-03, і цей порядок ГИНУВ тут —
        # блок контрасту перевпорядковував гілки (на низькому контрасті
        # «тональна» стає першою), і на екрані людина бачила чотири рівні
        # смуги без жодної ознаки, що одна з них у корпусі стоїть першою за
        # надійністю, а інша — п'ятою й позначена «advanced». Правило було в
        # коментарі й ні на що не впливало. after: ранг їде полем, і
        # перестановку відносно корпусу видно як факт, а не як випадковість.
        g["надійність_ранг"] = _РАНГ_K_COL_03.get(схема)
        гілки.append(g)

    вісь = блок["вісь_розходження"]
    згоди_нема = list(блок["згоди_нема"])
    if ясність is None:
        згоди_нема.append("ясність (muted/clear) загейтована K-PC-05: звуження за насиченістю "
                          "не робиться — розвилка тримається на самому value-контрасті")

    if not conv:
        # statement/editorial: мета не «лестити обличчю» — відкриваються гілки-мисматчі
        for схема in ТІЛЬКИ_STATEMENT:
            гілки.append(dict(схема=схема, вага="statement", вага_нп=0.0,
                коли=f"свідомий statement-хід під intent={intent}",
                застереження=СХЕМИ[схема]["ризик"],
                пропорція=пропорція(схема, домінантний, intent)))
        гілки.append(dict(схема="контраст-мисматч", вага="statement", вага_нп=0.0,
            коли="свідомо НЕ під контраст особи (одяг як фокус, не обличчя)",
            застереження="під conventional це промах PCA; під statement — законний вибір. "
                         "Реалізується як будь-яка щоденна схема, знята з-під контраст-матчу",
            пропорція=dict(стратегії=[dict(назва="колор-блок", **ПРОПОРЦІЯ["колор-блок"])],
                за_замовчуванням="колор-блок",
                нота="statement-мисматч найчастіше саме колор-блок: рівні поля як свідомий хід",
                провенанс="колор-блок тут — не дефолт-фольклор, а обраний statement")))
        вісь += (" | Крос-родовідна розвилка: PCA-лінія лестить обличчю (контраст-матч), "
                 "редакторська лінія цього не приймає взагалі. Тут її вирішує САМЕ intent.")

    # порядок: неперервна вага, далі порядок домінантного блоку корпусу (нічия за вагою —
    # саме той випадок «усі чотири рівноправні» середнього блоку), statement-гілки в кінці
    гілки.sort(key=lambda g: (_ПОРЯДОК_ВАГ[g["вага"]] == 3, -g.get("вага_нп", 0.0), g.pop("_порядок_блоку", 99)))
    for g in гілки:
        g.setdefault("надійність_ранг", _РАНГ_K_COL_03.get(g["схема"]))
    _пор = [g["надійність_ранг"] for g in гілки if g.get("надійність_ранг")]
    _переставлено = _пор != sorted(_пор)
    import trace as _СЛ
    if _яскравий_мк:
        _СЛ.запис("R-MUA-04", "бюджет інтересу йде через обличчя", "palette.розвилка",
                  значення="яскравий макіяж: акцентні гілки позначено «акцент приглушений», ваги не змінено",
                  сила=0.5, напрям="застереження, не переваження")
    _СЛ.запис("K-COL-03", "схема не та", "palette.розвилка",
              значення="гілки %s; ранги надійності %s" %
                       ([g["схема"] for g in гілки], _пор),
              напрям=("порядок корпусу перевпорядковано рівнем контрасту"
                      if _переставлено else "порядок збігається з корпусним"))
    return dict(контраст_рівень=домінантний, частки=частки, k_col_03_переставлено=_переставлено, value_gap=особа.get("value_gap"),
                ясність=(round(ясність, 2) if ясність is not None else None), intent=intent,
                гілки=гілки, вісь_розходження=вісь, згоди_нема=згоди_нема,
                провенанс="ваги ПОРЯДКОВІ, не виміряні; зв'язок контраст↔схема — переважно "
                          "однородовідний PCA (R-TYP-02), ринково валідований, БЕЗ golden-set "
                          "калібрування; опора на оптику лише для приобличчевого контрасту (K-CLR-02)")
