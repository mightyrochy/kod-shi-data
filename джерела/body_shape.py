"""Категорія FFIT і стан талії з виміряних обхватів (тема-1 §1–3, §17.3)."""
from decimal import Decimal as Десяткове


РЕЄСТР = {
    "межі": dict(t="T2", val=dict(дюйм="2.54", близькі="1", різниця="3.6",
                 найбільша="10", талія_груди="9", талія_стегна="10",
                 ложка_груди="2", ложка_талія="7", високе_стегно="1.193"),
                 прав=["K-BOD-00", "K-BOD-02"],
                 джерело="тема-1 §2–3; Sokolowski & Bettencourt 2020, Tables 7, 9"),
    "стани": dict(t="T2", val={"Hourglass": True, "Bottom Hourglass": True,
                 "Top Hourglass": True, "Spoon": True, "Triangle": False,
                 "Inverted Triangle": False, "Rectangle": False,
                 "Diamond": False, "Oval": False, None: None},
                 прав=["K-BOD-00", "K-BOD-02"], джерело="тема-1 §1, §3, §17.3"),
}
C = {к: Десяткове(з) for к, з in РЕЄСТР["межі"]["val"].items()}


def _категорія(груди, талія, стегна, високе):
    """Виконує каскад Table 9 у порядку публікації; входи — у дюймах."""
    гс, сг = груди - стегна, стегна - груди
    гт, ст = груди - талія, стегна - талія
    if гс <= C["близькі"] and сг < C["різниця"] and (гт >= C["талія_груди"] or ст >= C["талія_стегна"]):
        return "Hourglass"
    if C["різниця"] <= сг < C["найбільша"] and ст >= C["талія_груди"] and not високе:
        return "Bottom Hourglass"
    if C["близькі"] < гс < C["найбільша"] and гт >= C["талія_груди"]:
        return "Top Hourglass"
    if сг > C["ложка_груди"] and ст >= C["ложка_талія"] and високе:
        return "Spoon"
    if (сг >= C["різниця"] and 0 <= ст < C["талія_груди"]) or (гт < 0 and ст >= 0):
        return "Triangle"
    if гс >= C["різниця"] and гт < C["талія_груди"] and ст >= 0:
        return "Inverted Triangle"
    if сг < C["різниця"] and гс < C["різниця"] and 0 <= гт < C["талія_груди"] and 0 <= ст < C["талія_стегна"]:
        return "Rectangle"
    if ст < 0 and гт < 0:
        return "Diamond"
    if ст < 0 and гт >= 0:
        return "Oval"
    return None


def визначення(обхвати):
    """Дає категорію, стан талії й підставу без підстановки високого стегна.

    Без виміру перебирає обидва боки умови високого стегна. Віддає лише
    спільний стан талії; залежну від відсутнього входу категорію не називає.
    Десяткове обчислення зберігає рівність на опублікованих межах.
    """
    груди, талія, стегна = (Десяткове(str(обхвати[к])) / C["дюйм"]
                           for к in ("груди", "талія", "стегна"))
    вимір = обхвати.get("високе_стегно")
    варіанти = ((Десяткове(str(вимір)) / C["дюйм"] / талія >= C["високе_стегно"],)
                if вимір else (False, True))
    категорії = {_категорія(груди, талія, стегна, в) for в in варіанти}
    стани = {РЕЄСТР["стани"]["val"][к] for к in категорії}
    стан = next(iter(стани)) if len(стани) == 1 else None
    категорія = next(iter(категорії)) if len(категорії) == 1 else None
    if len(категорії) > 1:
        підстава = "high_hip_not_measured"
        чому = "високе стегно не виміряне; категорія FFIT залежить від відсутнього входу"
    elif категорія is None:
        підстава = "ffit_unclassified"
        чому = "каскад FFIT 2020 не дав категорії"
    else:
        підстава = "ffit_2020"
        чому = "FFIT 2020: " + категорія
    return dict(категорія=категорія, талія=стан, підстава=підстава, чому=чому)
