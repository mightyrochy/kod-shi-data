"""Категорія FFIT і стан талії з виміряних обхватів (тема-1 §1–3, §17.3)."""
from decimal import Decimal as Десяткове


РЕЄСТР = {
    "межі": dict(t="T2", val=dict(дюйм="2.54", близькі="1", різниця="3.6",
                 найбільша="10", талія_груди="9", талія_стегна="10",
                 ложка_груди="2", ложка_талія="7", високе_стегно="1.193"),
                 прав=["K-BOD-00", "K-BOD-02"],
                 джерело="тема-1 §2–3; Sokolowski & Bettencourt 2020, Tables 7, 9"),
    "стани": dict(t="T2", val={"Hourglass": True, "Bottom Hourglass": True,
                 "Top Hourglass": True, "Spoon": True, "Triangle": False,
                 "Inverted Triangle": False, "Rectangle": False,
                 "Diamond": False, "Oval": False, None: None},
                 прав=["K-BOD-00", "K-BOD-02"], джерело="тема-1 §1, §3, §17.3"),
}
C = {к: Десяткове(з) for к, з in РЕЄСТР["межі"]["val"].items()}


def _не(а):
    return None if а is None else not а


def _і(*а):
    """Кліні: хоч одне False — False; усі True — True; інакше None (вимір не розрізняє)."""
    return False if False in а else True if all(х is True for х in а) else None


def _або(*а):
    return True if True in а else False if all(х is False for х in а) else None


def _не_нижче(x, е, межа):
    """x >= межа: True/False — на всьому відрізку [x − е, x + е]; None — відрізок торкається межі з обох боків
    чи похибки нема (е None)."""
    # Імпорт у виклику: `силует_пропорції` через `fit` читає цей модуль — на верху файлу коло.
    from силует_пропорції import категорії_в_похибці   # одна точка «понад похибку» (ч13)
    к = категорії_в_похибці(x, е, (межа,))
    return True if к == (1,) else False if к == (0,) else None


def _не_вище(x, е, межа):
    return _не_нижче(-x, е, -межа)


def _нижче(x, е, межа):
    return _не(_не_нижче(x, е, межа))


def _вище(x, е, межа):
    return _не(_не_вище(x, е, межа))


def _сума(*е):
    """Похибка різниці двох обхватів несе похибки обох; однієї нема — нема й цієї."""
    return None if None in е else sum(е)


КАСКАД = ("Hourglass", "Bottom Hourglass", "Top Hourglass", "Spoon", "Triangle", "Inverted Triangle",
          "Rectangle", "Diamond", "Oval")


def _категорії(груди, талія, стегна, високе, е_г, е_т, е_с):
    """Об'єднує каскад за обома боками умови високого стегна, коли його не виміряно (`високе` None)."""
    можливі = ()
    for бік in ((високе,) if високе is not None else (False, True)):
        можливі += tuple(к for к in _каскад(груди, талія, стегна, бік, е_г, е_т, е_с) if к not in можливі)
    return можливі


def _каскад(груди, талія, стегна, високе, е_г, е_т, е_с):
    """Каскад Table 9 у порядку публікації над відрізками різниць обхватів ± похибка обох. Входи — у дюймах;
    `високе` — True/False (умова високого стегна); → кортеж можливих категорій (None — «каскад не дав
    категорії»). Категорія можлива, коли її умова не False і жодна попередня не True; кореляцію різниць
    (спільний обхват) не використовує, тож при похибках дає не вужчий набір, ніж точний."""
    гс, сг, гт, ст = груди - стегна, стегна - груди, груди - талія, стегна - талія
    е_гс, е_гт, е_ст = _сума(е_г, е_с), _сума(е_г, е_т), _сума(е_с, е_т)
    умови = (
        _і(_не_вище(гс, е_гс, C["близькі"]), _нижче(сг, е_гс, C["різниця"]),
           _або(_не_нижче(гт, е_гт, C["талія_груди"]), _не_нижче(ст, е_ст, C["талія_стегна"]))),
        _і(_не_нижче(сг, е_гс, C["різниця"]), _нижче(сг, е_гс, C["найбільша"]),
           _не_нижче(ст, е_ст, C["талія_груди"]), _не(високе)),
        _і(_вище(гс, е_гс, C["близькі"]), _нижче(гс, е_гс, C["найбільша"]), _не_нижче(гт, е_гт, C["талія_груди"])),
        _і(_вище(сг, е_гс, C["ложка_груди"]), _не_нижче(ст, е_ст, C["ложка_талія"]), високе),
        _або(_і(_не_нижче(сг, е_гс, C["різниця"]), _не_нижче(ст, е_ст, 0), _нижче(ст, е_ст, C["талія_груди"])),
             _і(_нижче(гт, е_гт, 0), _не_нижче(ст, е_ст, 0))),
        _і(_не_нижче(гс, е_гс, C["різниця"]), _нижче(гт, е_гт, C["талія_груди"]), _не_нижче(ст, е_ст, 0)),
        _і(_нижче(сг, е_гс, C["різниця"]), _нижче(гс, е_гс, C["різниця"]), _не_нижче(гт, е_гт, 0),
           _нижче(гт, е_гт, C["талія_груди"]), _не_нижче(ст, е_ст, 0), _нижче(ст, е_ст, C["талія_стегна"])),
        _і(_нижче(ст, е_ст, 0), _нижче(гт, е_гт, 0)),
        _і(_нижче(ст, е_ст, 0), _не_нижче(гт, е_гт, 0)),
    )
    можливі = []
    for категорія, умова in zip(КАСКАД, умови):
        if умова is not False:
            можливі.append(категорія)
        if умова is True:
            return tuple(можливі)
    return tuple(можливі) + (None,)


def визначення(груди, талія, стегна, високе_стегно=None, похибка=None):
    """Дає категорію, стан талії й підставу: категорію називає лише понад похибку обох вимірів кожної різниці.

    `похибка(вимір)` — похибка виміру в см (`груди`, `талія`, `стегна`, `високе_стегно`) чи None; продукт
    дає її через `силует_пропорції.похибка_виміру_тіла(t, вимір)` (одна точка, ч13), точний вхід (фікстура
    каскаду) — `lambda в: 0`. Не передано чи None — вимір «невідомо»: категорія не названа, `можливі` —
    усі, яких каскад не виключає. Без виміру високого стегна перебирає обидва боки його умови; віддає
    спільний стан талії, залежну від відсутнього входу категорію не називає. Десяткове обчислення
    зберігає рівність на опублікованих межах."""
    похибка = похибка or (lambda вимір: None)
    е_груди, е_талія, е_стегна, е_високе = (похибка(вимір) for вимір in
                                            ("груди", "талія", "стегна", "високе_стегно"))
    груди, талія, стегна = (Десяткове(str(з)) / C["дюйм"] for з in (груди, талія, стегна))
    е_г, е_т, е_с = (None if х is None else Десяткове(str(х)) / C["дюйм"] for х in (е_груди, е_талія, е_стегна))
    високе = None
    if високе_стегно:
        в = Десяткове(str(високе_стегно)) / C["дюйм"]
        частка = в / талія
        е_частки = None if None in (е_високе, е_т) else (
            частка * (Десяткове(str(е_високе)) / C["дюйм"] / в + е_т / талія))
        високе = _не_нижче(частка, е_частки, C["високе_стегно"])
    категорії = _категорії(груди, талія, стегна, високе, е_г, е_т, е_с)
    стани = {РЕЄСТР["стани"]["val"][к] for к in категорії}
    стан = next(iter(стани)) if len(стани) == 1 else None
    категорія = категорії[0] if len(категорії) == 1 else None
    if len(категорії) > 1:
        if None in (е_груди, е_талія, е_стегна):
            підстава = "body_error_unknown"
            чому = "похибки вимірів тіла невідомі; категорія FFIT не названа: " + ", ".join(map(str, категорії))
        elif високе is None and not any((е_груди, е_талія, е_стегна)):
            підстава = "high_hip_not_measured"
            чому = "високе стегно не виміряне; категорія FFIT залежить від відсутнього входу"
        else:
            підстава = "body_within_error"
            чому = "вимір у межах похибки не розрізняє категорій FFIT: " + ", ".join(map(str, категорії))
    elif категорія is None:
        підстава = "ffit_unclassified"
        чому = "каскад FFIT 2020 не дав категорії"
    else:
        підстава = "ffit_2020"
        чому = "FFIT 2020: " + категорія
    return dict(категорія=категорія, талія=стан, підстава=підстава, чому=чому, можливі=категорії)
