# -*- coding: utf-8 -*-
"""ЗБИРАННЯ ТАБЛИЦІ КАТАЛОГУ (Ш-1, рішення власника 27.09.2026) — побудова, яку кличе збирач.

Таблицю будує збирач (`build_артефакт._покласти_таблицю`) з того самого фіду тим самим кодом, що й
продукт на льоту, звіряє відновлену з побудованою до знака і кладе у вантаж; продукт її відновлює
(`таблиця_каталогу.база`). Формат, ключ і застарілість — докстрінг `таблиця_каталогу`.

ЧОМУ ОКРЕМИЙ МОДУЛЬ (3.3, К-4). Доти `зібрати` стояла в `таблиця_каталогу` і лінивим імпортом кликала
`feed`/`фід_каталог`, які самі читають `таблиця_каталогу` — цикл імпортів ядра. Побудова стоїть над
читанням фіду, відновлення — під ним; модулі розведено за цим напрямом, поведінка та сама.
"""
import json as _json
import os as _os

import таблиця_каталогу as _ТК


def зібрати(шлях_фіду, тека=None, байти_модулів=None):
    """Будує таблицю з фіду тим самим кодом, що й продукт на льоту, і звіряє її.

    `байти_модулів` — {ім'я: байти}, як модулі їдуть у вантаж (збирач стрипає їх); без
    нього — файли теки як є (прогін у джерелах). Повертає словник таблиці; падає, коли
    відновлена з таблиці база хоч на знак розходиться з побудованою."""
    import builtins as _bi
    import trace as _СЛ
    import feed as _Ф, фід_каталог as _ФК, фід_розбір as _ФР, фід_слот as _ФС
    тека = тека or _os.path.dirname(_os.path.abspath(_ФК.__file__))
    import tempfile as _tf
    кеш_кол = _os.path.join(_tf.mkdtemp(), "кеш_кольорів.json")   # порожній, як у продукті
    with open(кеш_кол, "w", encoding="utf-8") as f:
        f.write("{}")
    відкрито, _open, _stat = [], _bi.open, _os.stat

    def _слідкувати(ф, *а, **к):
        відкрито.append(ф)
        return _open(ф, *а, **к)

    # ПИТАНІ Й ВІДСУТНІ ФАЙЛИ — ТЕЖ ВХІД: `фід_кадр_колір.читати_кадри` питає
    # `каталог_кадри.json(.gz)` через `_os.path.exists`, і без файла база інша, ніж із ним.
    # Файл, якого при побудові не було, лягає в ключ як відсутній — коли він з'явиться,
    # таблиця застаріє, а не вживеться мовчки (`_os.path.exists`/`getmtime` кличуть `_os.stat`)
    def _слідкувати_stat(ф, *а, **к):
        відкрито.append(ф)
        return _stat(ф, *а, **к)
    # кеші читачів файлів порожні — інакше файл, прочитаний раніше в цьому процесі, не
    # відкрився б під гачком і випав би з ключа (так випало збагачення на першій пробі)
    import фід_збагачення as _ФЗ, фід_фото as _ФФ, фід_кадр_колір as _ФКК, назва_речі as _НР
    for к_ in (_ФЗ.ЗБАГАЧЕННЯ_КЕШ, _ФФ.ПОКАЗ_КЕШ, _ФКК.КАДРИ_КЕШ, _НР.КАРТКИ_КЕШ, _ФС.ТИП_КЕШ):
        к_.clear()
    було_увімк, було = _СЛ.УВІМК, _СЛ.ЗАПИСИ
    _СЛ.почати()
    _bi.open, _os.stat = _слідкувати, _слідкувати_stat
    try:
        зб = _Ф.читати_збагачення()
        б = _ФК.прочитати_каталог(шлях_фіду, 0, кеш_кол, зб)
    finally:
        _bi.open, _os.stat = _open, _stat
        слід = [dict(з) for з in _СЛ.ЗАПИСИ]
        _СЛ.УВІМК, _СЛ.ЗАПИСИ = було_увімк, було
        _os.remove(кеш_кол)
        _os.rmdir(_os.path.dirname(кеш_кол))
    тип_кеш_б = list(_ФС.ТИП_КЕШ.items())
    офери = _ФР.офери_фіду(шлях_фіду)
    поз = {o["id"]: і for і, o in enumerate(офери)}
    записи = б["каталог"]
    без_оферу = [r["id"] for r in записи if r["id"] not in поз]
    if без_оферу:
        raise SystemExit("таблиця каталогу: записи без оферу у фіді — %s" % без_оферу[:5])
    # ── РІЗНИЦЯ ДО ОФЕРУ, СТОВПЧИКАМИ ────────────────────────────────────────
    н = len(записи)
    імена, н_імені = [], {}
    кортежі, порядки, номер, порядок, стовпці = {}, [], {}, [], {}
    for і, r in enumerate(записи):
        o = офери[поз[r["id"]]]
        for к in r:
            if к not in н_імені:
                н_імені[к] = len(імена)
                імена.append(к)
        к_ = tuple(н_імені[к] for к in r)
        if к_ not in номер:
            номер[к_] = len(порядки)
            порядки.append(list(к_))
        порядок.append(номер[к_])
        for к, v in r.items():
            for ш in _ТК.шляхи_кортежів(v):
                кортежі.setdefault(к, set()).add(ш)
            if к in o and _ТК.однакові(o[к], v):
                continue
            if _ТК.позначка(v):
                raise SystemExit("таблиця каталогу: значення поля %s має форму позначки таблиці" % к)
            фото = o.get("фото") or []
            стовпці.setdefault(к, {})[і] = ([_ТК.ПОСИЛАННЯ, "фото", фото.index(v)]
                                           if isinstance(v, str) and v in фото else v)
    поля = {}
    for к, зн in sorted(стовпці.items()):
        if 2 * len(зн) >= н:
            поля[к] = {"щ": [зн.get(і, _ТК.ПРОПУСК) for і in range(н)]}
        else:
            іі = sorted(зн)
            поля[к] = {"і": іі, "з": [зн[і] for і in іі]}
    # ── КЕШ ТИПІВ: КЛЮЧ — НОМЕРОМ ОФЕРУ, ДЕ ВІН ТАКИЙ САМИЙ ─────────────────────
    перший = {}
    for і, o in enumerate(офери):
        перший.setdefault((str(o.get("категорія", "")), _ФС.назва_суду(o)), і)
    тк = [([перший[(кат, назва)], слот, тип] if (кат, назва) in перший else [кат, назва, слот, тип])
          for (кат, назва, слот), тип in тип_кеш_б]
    корінь = _os.path.abspath(тека)
    питані = {_os.path.abspath(_os.fspath(ф)) for ф in відкрито if isinstance(ф, (str, _os.PathLike))}
    дані = [ф for ф in питані
            if _os.path.dirname(ф) == корінь and not ф.endswith(".py") and not _os.path.isdir(ф)
            and ф not in (_os.path.abspath(шлях_фіду), _os.path.abspath(кеш_кол))]
    т = dict(версія=_ТК.ВЕРСІЯ, фід_ім=_os.path.basename(шлях_фіду),
             ключ=_ТК.ключ(шлях_фіду, тека, байти_модулів, дані),
             записи=[поз[r["id"]] for r in записи], імена=імена, поля=поля,
             порядки=порядки, порядок=порядок,
             кортежі={к: sorted(list(ш) for ш in шш) for к, шш in sorted(кортежі.items())},
             лічильники={к: v for к, v in б.items() if к != "каталог"},
             кортежі_лічильників={к: sorted(list(ш) for ш in set(_ТК.шляхи_кортежів(v)))
                                  for к, v in б.items() if к != "каталог"},
             порядок_бази=list(б), слід=слід, тип_кеш=тк)
    # ── ЗВІРКА: ТЕ, ЩО ВІДНОВИТЬ ПРОДУКТ, — ТА САМА БАЗА ДО ЗНАКА ─────────────
    т_json = _json.loads(_json.dumps(т, ensure_ascii=False))
    відн = _ТК.відновити(т_json, офери)
    if _ТК.тип_кеш(т_json, офери) != тип_кеш_б:
        raise SystemExit("таблиця каталогу: відновлений кеш типів розходиться з побудованим")
    if not _ТК.однакові(відн, б):
        різні = [r["id"] for r, в in zip(б["каталог"], відн.get("каталог") or []) if not _ТК.однакові(r, в)]
        raise SystemExit("таблиця каталогу: відновлена база розходиться з побудованою — записів %d "
                         "(перші: %s); лічильники однакові: %s"
                         % (len(різні), різні[:5], all(_ТК.однакові(б[к], відн.get(к)) for к in б if к != "каталог")))
    return т
