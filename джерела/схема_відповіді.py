"""схема_відповіді.py — єдине джерело опису кожної форми відповіді моделі-стилістки.

Об'єднує в одній структурі для кожної форми відповіді:
  - фразу формату в промпті (en / uk);
  - посилання на схему протоколу;
  - функцію розбору відповіді моделі;
  - сторож (валідацію розібраного результату проти правил / суду / схеми).
"""
from dataclasses import dataclass
from typing import Any, Callable, Optional

import протокол as _ПР

# Сталі фраз формату промпту
ФОРМА_JSON = "Відповідь — лише один JSON-обʼєкт за «схема_відповіді», без пояснень і без ```."
ФОРМА_JSON_EN = "The answer is one JSON object following \"answer_schema\", without explanations and without ```."
ФОРМИ_EN = {
    "текст": "The answer is plain text laid out as the rules say, not JSON.",
    "картинка": "The answer is one image and no text.",
}


@dataclass(frozen=True)
class СхемаВідповіді:
    """Опис форми відповіді моделі: фраза промпту, розбір і сторож."""
    ід: str
    назва: str
    відповідь_як: str = "json"
    схема_протоколу: Optional[str] = None
    фраза_формату_en: str = ФОРМА_JSON_EN
    фраза_формату_uk: str = ФОРМА_JSON
    розбір: Optional[Callable] = None
    сторож: Optional[Callable] = None

    def фраза_формату(self, en: bool = False) -> str:
        """Повертає формулювальний рядок для промпту відповідною мовою."""
        if self.відповідь_як in ФОРМИ_EN:
            return ФОРМИ_EN[self.відповідь_як]
        return self.фраза_формату_en if en else self.фраза_формату_uk

    def виконати_розбір(self, текст_або_вхід: Any, **контекст) -> Any:
        """Виконує розбір сирої відповіді моделі."""
        if self.розбір is not None:
            return self.розбір(текст_або_вхід, **контекст)
        return текст_або_вхід

    def перевірити(self, об: Any, **контекст) -> Any:
        """Перевіряє розібраний об'єкт сторожем схеми."""
        if self.сторож is not None:
            return self.сторож(об, **контекст)
        return {"ок": True}


# ── ФУНКЦІЇ РОЗБОРУ ТА СТОРОЖІВ ───────────────────────────────────────────────

def _розбір_образи_v1(текст, кандидати=None, каталог=None, просили=None, d=None):
    """Розбір образів із тексту відповіді з фільтрацією за chosen та стелею просили."""
    import pipeline as _PL
    _розбір_відп = _PL.образи_з_тексту(текст, кандидати=кандидати, каталог=каталог)
    if _розбір_відп and isinstance(просили, int) and просили > 0:
        _з_ід_в = [р for р in _розбір_відп if р.get("ід")]
        if len(_з_ід_в) > просили:
            _обр_в = [str(x.get("ід") or "") for x in
                      ((_ПР.розбір_за_схемою(текст, "ОБРАЗИ_V1")[0] or {}).get("обрано") or [])
                      if isinstance(x, dict)]
            _бачені, _за_вибором = set(), []
            for р in _з_ід_в:
                if р.get("ід_відповіді") in _обр_в and р["ід_відповіді"] not in _бачені:
                    _бачені.add(р["ід_відповіді"])
                    _за_вибором.append(р)
            _вибр = {id(р) for р in _за_вибором}
            _лишити = {id(р) for р in (_за_вибором + [р for р in _з_ід_в if id(р) not in _вибр])[:просили]}
            if d is not None:
                d["_понад_просили"] = dict(
                    просили=просили,
                    дала=len(_з_ід_в),
                    **({"за_обраним": min(len(_за_вибором), просили)} if _за_вибором else {}),
                    не_взято=[dict(підпис=р.get("підпис"), ід=list(р["ід"]))
                              for р in _з_ід_в if id(р) not in _лишити]
                )
            _розбір_відп = [р for р in _розбір_відп if not р.get("ід") or id(р) in _лишити]
    return _розбір_відп


def _сторож_образи_v1(текст, образи=None, джерело_образу=None, розбір_блоків=None, обрізано=False):
    """Сторож форми ОБРАЗИ_V1: валідація за схемою, діагностика обривів, ехо та пулу."""
    _об_в, _чому_в, _нот_в = _ПР.розбір_за_схемою(текст, "ОБРАЗИ_V1")
    _пом_в = []
    if isinstance(_об_в, dict) and isinstance(_об_в.get("образи"), list):
        _пом_в = _ПР.перевірити(_ПР.СХЕМИ["ОБРАЗИ_V1"], _об_в)
        if not _пом_в and not образи and not джерело_образу:
            _не_з_пулу = [н for б in ((розбір_блоків or {}).get("без_id") or [])
                          for н in (б.get("невідомі") or [])]
            _пом_в = [dict(де="образи[].речі", що="items_not_in_pool(%s)" % ", ".join(
                "«%s»" % н for н in _не_з_пулу[:6]))]
    elif not образи and not джерело_образу:
        _пом_в = [dict(де="корінь", що=(_чому_в or "no_outfits"))]

    _пом_в = list(_нот_в.get("ехо") or []) + _пом_в
    повторний = None
    if _пом_в and not образи and not джерело_образу:
        повторний = _ПР.помилка_формату(_пом_в[:8], відповідь="ОБРАЗИ_V1")

    return {
        "об": _об_в,
        "чому": _чому_в,
        "нормалізовано": _нот_в.get("нормалізовано") or [],
        "обрізано": bool(_нот_в.get("обрізано") or обрізано),
        "помилки": _пом_в,
        "повторний_виклик": повторний,
    }


def _розбір_вибір_v1(текст, вибір_над=None, кандидати=None, каталог=None):
    """Розбір вибору з JSON."""
    import pipeline as _PL
    return _PL.вибір_з_json(текст, вибір_над or {}, кандидати=кандидати, каталог=каталог)


def _сторож_вибір_v1(вибір, вибір_над=None):
    """Сторож обраного образу."""
    if not isinstance(вибір, dict) or not вибір.get("ід"):
        return {"ок": False, "чому": "no_outfit_chosen"}
    return {"ок": True, "ід": вибір.get("ід")}


def _розбір_доповнення_v1(текст, до_вибору=True, попередній_вердикт=None):
    """Розбір форми доповнення (ремонт повноти)."""
    import pipeline as _PL
    if до_вибору:
        _дп = _ПР.розбір_за_схемою(текст, "ДОПОВНЕННЯ_V1")[0]
        _дп = _PL.доповнити(_дп, попередній_вердикт) if isinstance(_дп, dict) else None
        _об_дв = _дп[0] if _дп else _ПР.розбір_за_схемою(текст, "ОБРАЗИ_V1")[0]
        _зл = (_PL.злити_з_неторканими(_об_дв, попередній_вердикт)
               if isinstance(_об_дв, dict) else None)
        if _зл:
            return _зл[0], _зл[1]
        return None, None
    else:
        _дп_пв = _ПР.розбір_за_схемою(текст, "ДОПОВНЕННЯ_V1")[0]
        _дп_пв = _PL.доповнити_обраний(_дп_пв, попередній_вердикт) if isinstance(_дп_пв, dict) else None
        if _дп_пв:
            return _дп_пв[0], None
        _об_пв = _ПР.розбір_за_схемою(текст, "ОБРАЗИ_V1")[0]
        _дн = _PL.донести_ходи_кодом(_об_пв, попередній_вердикт) if isinstance(_об_пв, dict) else None
        if _дн:
            return _дн, None
        return None, None


def _розбір_опис_відповідь_v1(текст, кандидати=None, каталог=None, склад=None, запасні=False):
    """Розбір опису відповіді з JSON."""
    import pipeline as _PL
    _опис_відп = _PL.опис_відповідь_з_json(
        текст, кандидати=кандидати, каталог=каталог, склад=склад, запасні=запасні
    )
    if _опис_відп.get("заміна") and not запасні:
        _опис_відп = _PL.без_прози_заміни(_опис_відп)
    return _опис_відп


def _розбір_руки_без_коду(текст, T=None, перелік=None, паспорт=None):
    """Розбір відповіді руки без коду (проза або перелік); проза без мітки задачі — у `проза_руки`."""
    import pipeline as _PL
    import руки_без_коду as _РБК
    import річ_з_фото as _РФ

    проза = _РБК.проза_руки(текст)
    в = _PL.перевірити_образ_моделі(проза, T, перелік=перелік)
    в["проза_руки"] = проза
    в["джерело_образу"] = (
        "текст моделі (без каталогу), речі — окремим викликом"
        if (в.get("розбір") or {}).get("перелік_моделі")
        else "текст моделі (без каталогу), речі — розбором прози"
    )
    _рр, _стан_її = _РФ.впізнати_в_тексті(в.get("речі"), (паспорт or {}).get("речі_з_фото"))
    if _стан_її:
        в["речі"], в["її_річ"] = _рр, _стан_її
    return в


