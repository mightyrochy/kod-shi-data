def фраза_формату(назва: Optional[str] = None, як: str = "json", en: bool = False) -> str:
    """Повертає фразу формату для промпту за схемою або видом відповіді."""
    if як in ФОРМИ_EN:
        return ФОРМИ_EN[як]
    if назва and назва in СХЕМИ_ВІДПОВІДІ:
        return СХЕМИ_ВІДПОВІДІ[назва].фраза_формату(en=en)
    return ФОРМА_JSON_EN if en else ФОРМА_JSON


def схема_за_назвою(назва: Optional[str]) -> СхемаВідповіді:
    """Повертає схему відповіді за назвою чи ідентифікатором."""
    if not назва:
        return СХЕМИ_ВІДПОВІДІ["ОБРАЗИ_V1"]
    if назва in СХЕМИ_ВІДПОВІДІ:
        return СХЕМИ_ВІДПОВІДІ[назва]
    верхній = str(назва).strip().upper()
    if верхній in СХЕМИ_ВІДПОВІДІ:
        return СХЕМИ_ВІДПОВІДІ[верхній]
    нижній = str(назва).strip().lower()
    for с in СХЕМИ_ВІДПОВІДІ.values():
        if с.ід == нижній or с.назва.lower() == нижній:
            return с
    return СХЕМИ_ВІДПОВІДІ["ОБРАЗИ_V1"]


def визначити_схему(d: Any) -> СхемаВідповіді:
    """Визначає форму відповіді моделі за вхідними даними виклику."""
    if not isinstance(d, dict):
        return СХЕМИ_ВІДПОВІДІ["ОБРАЗИ_V1"]
    if d.get("заміна") and str(d.get("рука")) in ("3", "4"):
        return СХЕМИ_ВІДПОВІДІ["ЗАМІНА_БЕЗ_КАТАЛОГУ"]
    if d.get("заміна"):
        return СХЕМИ_ВІДПОВІДІ["ЗАМІНА"]
    if d.get("вибір_речей") and not d.get("текст_моделі"):
        return СХЕМИ_ВІДПОВІДІ["вибір_речей"]
    if d.get("спроба_повноти") and d.get("текст_моделі") and isinstance(d.get("попередній_вердикт"), dict):
        return СХЕМИ_ВІДПОВІДІ["ДОПОВНЕННЯ_V1"]
    відповідь = str(d.get("відповідь") or "")
    if відповідь == "ВИБІР_V1":
        return СХЕМИ_ВІДПОВІДІ["ВИБІР_V1"]
    if відповідь == "ОПИС_ВІДПОВІДЬ_V1":
        return СХЕМИ_ВІДПОВІДІ["ОПИС_ВІДПОВІДЬ_V1"]
    if відповідь in СХЕМИ_ВІДПОВІДІ:
        return СХЕМИ_ВІДПОВІДІ[відповідь]
    return СХЕМИ_ВІДПОВІДІ["ОБРАЗИ_V1"]


