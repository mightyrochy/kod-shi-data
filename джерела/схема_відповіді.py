def вибір_образів(обрано):
    """`ОБРАЗИ_V1.обрано` → (ід обраних образів, скільки записів не прочитано). Запис вибору — обʼєкт з «ід», та
    сама форма, що в скелеті ремонту (`{"id": …, "why": …}`); рядок («id=o6», «o6») розбір не тлумачить (К-1), а лічить."""
    записи = обрано if isinstance(обрано, list) else []
    ід = [str(х["ід"]) for х in записи if isinstance(х, dict) and х.get("ід")]
    return ід, len(записи) - len(ід)


def понад_просили(розбір, обрано, просили):
    """Образи розбору з `ід`, яких більше за `просили` → (розбір у межах `просили`, слід `_понад_просили`).

    Лишаються образи, названі у «chosen»; місця, яких вибір не заповнив, бере порядок відповіді. Це типова, і слід
    її називає: `за_порядком` — скільки образів узято порядком, а не вибором; `обрано_не_прочитано` —
    записи «chosen», що не є обʼєктом з «id». Доти ремонт, що назвав вибір рядками, мовчки йшов за першими N."""
    з_ід = [р for р in розбір if р.get("ід")]
    ід_вибору, не_прочитано = вибір_образів(обрано)
    бачені, за_вибором = set(), []
    for р in з_ід:
        if р.get("ід_відповіді") in ід_вибору and р["ід_відповіді"] not in бачені:
            бачені.add(р["ід_відповіді"])
            за_вибором.append(р)
    вибр = {id(р) for р in за_вибором}
    лишити = {id(р) for р in (за_вибором + [р for р in з_ід if id(р) not in вибр])[:просили]}
    за_обраним = min(len(за_вибором), просили)
    слід = dict(
        просили=просили,
        дала=len(з_ід),
        **({"за_обраним": за_обраним} if за_вибором else {}),
        **({"за_порядком": просили - за_обраним} if за_обраним < просили else {}),
        **({"обрано_не_прочитано": не_прочитано} if не_прочитано else {}),
        не_взято=[dict(підпис=р.get("підпис"), ід=list(р["ід"])) for р in з_ід if id(р) not in лишити])
    return [р for р in розбір if not р.get("ід") or id(р) in лишити], слід


def _сторож_образи_v1(текст, образи=None, джерело_образу=None, розбір_блоків=None, обрізано=False):
    """Сторож форми ОБРАЗИ_V1: валідація за схемою, діагностика обривів, ехо та пулу."""
    _об_в, _чому_в, _нот_в = _ПР.розбір_за_схемою(текст, "ОБРАЗИ_V1")
    _пом_в = []
    if isinstance(_об_в, dict) and isinstance(_об_в.get("образи"), list):
        _пом_в = _ПР.перевірити(_ПР.СХЕМИ["ОБРАЗИ_V1"], _об_в)
        if not _пом_в and not образи and not джерело_образу:
            _не_з_пулу = [н for б in ((розбір_блоків or {}).get("без_id") or [])
                          for н in (б.get("невідомі") or [])]
            _пом_в = [dict(де="образи[].речі", що="items_not_in_pool(%s)" % ", ".join(
                "«%s»" % н for н in _не_з_пулу[:6]))]
    elif not образи and not джерело_образу:
        _пом_в = [dict(де="корінь", що=(_чому_в or "no_outfits"))]

    _пом_в = list(_нот_в.get("ехо") or []) + _пом_в
    повторний = None
    if _пом_в and not образи and not джерело_образу:
        повторний = _ПР.помилка_формату(_пом_в[:8], відповідь="ОБРАЗИ_V1")

    return {
        "об": _об_в,
        "чому": _чому_в,
        "нормалізовано": _нот_в.get("нормалізовано") or [],
        "обрізано": bool(_нот_в.get("обрізано") or обрізано),
        "помилки": _пом_в,
        "повторний_виклик": повторний,
    }


