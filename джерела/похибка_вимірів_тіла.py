def запис(вид, назва):
    """Запис величини цілком (копія): число, джерело, місце в ньому, спосіб виміру, примітка.

    Невідоме ім'я — KeyError, а не None: одрук у точці підключення інакше читався б як «невідомо»."""
    return dict(РЕЄСТР[вид][назва])


def похибка(вид, назва):
    """Похибка величини — 1 SD (обхват — см; рівень — частка зросту) — або None, коли джерела нема."""
    return РЕЄСТР[вид][назва]["val"]


def похибка_якщо_є(вид, назва):
    """Як `похибка`, але величина, якої запис не веде (зріст, пах — оцінка частки стегон), — None («невідомо»),
    а не KeyError: читачі спрямовують сюди всі свої виміри, не лише названі в записі."""
    return РЕЄСТР[вид].get(назва, {}).get("val")
