"""ТІРИ Й СТЕЛЯ СИЛИ: тір константи → стеля сили правила, друга стеля від корпусу,
гейт без доказу і `регістр()` — ЄДИНА функція, що вирішує регістр знахідки.

ЧОМУ ЦЕЙ ФАЙЛ Є (20.09.2026, хвиля стандарту, СТАНДАРТ_КОДУ §5 п.16). `реєстр_правил.py`
(1 567 рядків) розділено на шість модулів за відповідальністю ЧИСТИМ перенесенням:
кожен вузол тут — байт у байт той самий, що стояв у `реєстр_правил.py@d1dbd9a`;
`реєстр_правил` лишився фасадом і реекспортує кожне ім'я. Інваріант «сила ≤
верифікація» тримається в одному місці, як і доти, — тепер це місце має власне ім'я.

ЩО ТУТ (рядки — за `реєстр_правил.py` до поділу):
  · СТЕЛЯ_ЗА_ТІРОМ, _ТІР_НОРМА, `_норм_тір` (751–789);
  · `_тір_правила`, `стеля_сили`, `_обмежити_тіром`, `_обмежити_корпусом`,
    ГЕЙТ_БЕЗ_ДОКАЗУ, `_гейт_без_доказу`, `регістр` (800–932).
Читає REGISTRY і `_за_кого` з `реєстр_константи`, таблицю політики і ПОРЯДОК —
з `реєстр_політика`; ребра лише вперед, без кіл.

ЧОГО ТУТ НЕМА: `_за_кого` стоїть біля словника, який читає (`реєстр_константи`);
шкала ваги і `_зн` — `реєстр_сила`; намір — `реєстр_намір`; осі — `реєстр_осі`.
"""
from реєстр_політика import МЕЖА_ЛЮДИНИ, ПОРЯДОК, _політика
from реєстр_константи import REGISTRY, _за_кого

# ── ТІР КОНСТАНТИ → СТЕЛЯ СИЛИ ПРАВИЛА (тут REGISTRY нарешті щось ВИРІШУЄ) ──
# Досі REGISTRY був довідкою для людського ока: код читав із нього значення (C[...]),
# а ТІР не впливав ні на що. Інваріант «сила ≤ верифікація» тримався лише двома
# іншими способами (маржа проти смуги + регістр за ID правила), і правило на
# некаліброваній T3-константі спокійно виходило як "strong".
# Тепер тір — гейт: правило не може бути сильнішим за найслабшу константу під ним.
СТЕЛЯ_ЗА_ТІРОМ = {"T1": "hard", "T2": "strong", "T3": "soft"}
# ПЕРЕВІРЕНО 12.09.2026 (Н-outfit-1-085): ключ "T1" ЖИВИЙ, хоч у REGISTRY цього
# модуля жодної T1-константи нема (25×T3 + 1×T2). Стеля рахується по реєстру ТОГО
# модуля, звідки прийшла знахідка (`стеля_сили(правило, reg)`), а T1-константи там
# є: `outer.РЕЄСТР["fp_входів_мін"]` віддає K-OUT-15 стелю `hard`, і саме вона
# дозволяє темі-11:366 її силу. Тому ключ лишається, і ця нотатка — щоб наступний
# читач не зніс його як мертвий, побачивши лише REGISTRY ядра.
# `default` стелею не буває: жоден тір її не видає. Вона приходить із КОРПУСУ
# як заявлена сила правила й може бути лише ЗНИЖЕНА тіром до soft/hint.

# ЗНАЙДЕНО ПЕРЕВІРКОЮ КОДУ ПРОТИ КОРПУСУ: `_тір_правила` робив
# `("T1","T2","T3").index(t)` і падав ValueError на будь-якому іншому рядку. А інші
# рядки в реєстрах Є: "conventional" (посадка ×4, силует ×9, palette ×7, outfit ×5),
# "editorial", "визначення" і "T2-підлога" (координація). Прямий виклик
# `_тір_правила("K-COMP-01", координація.РЕЄСТР)` кидав виняток. Не падало лише тому,
# що координація свій реєстр у машинерію НЕ передавала — тобто інваріант там просто
# не працював, а перший, хто його підключить, дістав би краш.
# Тепер тір нормалізується, і кожен клас названий:
_ТІР_НОРМА = {
 "T1": "T1", "T2": "T2", "T3": "T3", "T4": "T3",
 "T2-підлога": "T2",       # підлога, виведена з T2-виміру — доказ той самий
 "conventional": "T3",     # конвенція ремесла = найслабший доказовий клас
 "editorial": "T3",
 "визначення": None,       # НЕ доказ і не його брак: дефініційна константа
                           # (напр. «менше двох слотів — пари не існує»). Вона не
                           # може ні підняти, ні опустити силу правила.
 "—": "T3", None: "T3",    # тір не проставлено -> вважаємо найслабшим
}

def _норм_тір(t):
    """Тір -> клас доказу, або None для дефініційних. Невідомий рядок — найслабший
    клас, і це навмисно: незнайомий тір не має права давати правилу більше прав."""
    return _ТІР_НОРМА.get(t, "T3")

def _тір_правила(правило, reg=None):
    """`reg` — реєстр констант. Параметр доданий, щоб інший модуль правил (посадка.py)
    проганяв СВОЇ константи через ЦЮ саму машинерію інваріанта, а не копіював її:
    копія розійшлась би з оригіналом при першій же зміні, і «сила ≤ верифікація»
    трималась би у двох місцях по-різному."""
    reg = REGISTRY if reg is None else reg
    тіри = [_норм_тір(v.get("t")) for v in reg.values() if правило in _за_кого(v)]
    тіри = [t for t in тіри if t]        # дефініційні константи не голосують
    if not тіри: return None
    return min(тіри, key=lambda t: ("T1", "T2", "T3").index(t) * -1)   # найслабший

def стеля_сили(правило, reg=None):
    """Максимальна сила, на яку правило має право за своєю доказовою базою."""
    т = _тір_правила(правило, reg)
    return СТЕЛЯ_ЗА_ТІРОМ.get(т) if т else None

def _обмежити_тіром(правило, сила, reg=None):
    стеля = стеля_сили(правило, reg)
    if стеля is None or сила in ("ok", "питання", "утримано"): return сила, None
    if ПОРЯДОК.index(сила) >= ПОРЯДОК.index(стеля): return сила, None
    return стеля, ("сила знижена з «%s» до «%s»: правило стоїть на константі тіру %s "
                   "(сила ≤ верифікація)" % (сила, стеля, _тір_правила(правило, reg)))


def _обмежити_корпусом(правило, сила, заявлена=None):
    """Другий бік того самого інваріанта (Н-02-05, крок 4 Н-V23-047): емісія не має
    права видати правило СИЛЬНІШИМ, ніж його називає САМ КОРПУС.

    Стеля тіру ловить «доказ під правилом слабкий»; ця — «корпус сказав менше, ніж
    каже код». Дві різні дірки, і друга вже була відкрита: `accessory` емітував
    K-WEA-05 і K-WEA-06 силою `strong` там, де тема-10:1605 і тема-10:1625 дають
    обом `default`. Стеля тіру це зараз перекриває (T3 → soft), але перекриває
    ВИПАДКОВО — досить комусь оголосити під правилом T2-константу, і заявка коду
    знову пішла б понад корпус. Тому стеля береться з того самого рядка політики,
    де вже стоїть `джерело`."""
    к = _політика(правило).get("сила_корпусу")
    if not к or сила in ("ok", "питання", "утримано"): return сила, None
    заявлена = сила if заявлена is None else заявлена
    джерело = _політика(правило).get("джерело") or "джерело не названо"
    if сила in ПОРЯДОК and ПОРЯДОК.index(сила) < ПОРЯДОК.index(к):
        return к, ("сила знижена з «%s» до «%s»: стільки дає правилу корпус (%s)"
                   % (сила, к, джерело))
    # ── ЧОМУ ЦЕ ПОЛЕ БУЛО ПОРОЖНЄ ЗАВЖДИ (19.09.2026, РВ-5 З-5) ──────────────
    # Виміряно пробою `аудит/проби/рв5_стеля_корпусу.py`: у жодній із шести
    # стендових сцен `стеля_корпусу` не з'являлась ЖОДНОГО разу, працювала лише
    # `стеля_тіру`. Причина не в тому, що код ніде не заявляє понад корпус, — він
    # заявляє: `accessory` кличе K-WEA-05 і K-WEA-06 силою `strong` там, де
    # тема-10:1605/1625 дають обом `default`, `fit` кличе K-FIT-01 силою `strong`
    # при корпусному `soft`. Причина в ПОРЯДКУ: тір іде першим (і це навмисно,
    # див. `_зн`), а в КОЖНОМУ рядку таблиці стеля тіру (T3 → soft) не вища за
    # силу корпусу. Друга стеля діставала вже зрізану силу, і їй не лишалось чого
    # знижувати — заявка коду понад корпус зникала за нотою про тір.
    # Стеля корпусу могла б ЗНИЗИТИ силу лише там, де під правилом оголошено
    # константу T1/T2, а корпус при цьому свідомо дає менше; жодного такого рядка
    # в таблиці сьогодні нема, і це факт про таблицю, а не привід мовчати.
    # ЩО СТАЛО: стеля міряється ще й проти ЗАЯВЛЕНОЇ сили (тієї, з якою емітент
    # покликав `_зн`). Чинна сила не змінюється — вона й доти була мінімумом обох
    # стель, — але перевищення заявки над корпусом більше не невидиме.
    if (заявлена in ПОРЯДОК and сила in ПОРЯДОК
            and ПОРЯДОК.index(заявлена) < ПОРЯДОК.index(к)):
        return сила, ("емісія заявила «%s», а корпус дає правилу «%s» (%s); чинну "
                      "силу «%s» поставила стеля тіру — вона не вища за корпусну, тож "
                      "знижувати тут уже нічого. Заявка коду понад корпус — факт про "
                      "ЕМІСІЮ, і тепер він названий, а не схований за нотою тіру"
                      % (заявлена, к, джерело, сила))
    return сила, None

# Сили, у яких знахідка ще виходить як гейт. Репліка не має "strong/hard" — вона має
# впевненість, не силу заборони.
#
# ── НЕВІДОМИЙ ТІР БІЛЬШЕ НЕ ДАЄ ПРАВА НА ГЕЙТ (перевірка V23, наряд Н-V23-046) ──
# ЩО ТУТ СТОЯЛО: регістр питав ЛИШЕ карту — «написано гейт і сила hard/strong,
# отже блокуємо». Тір під правилом не питали жодного разу, і саме на найсильнішому
# регістрі інваріант «сила ≤ верифікація» не діяв узагалі. Зміряно на картах
# чотирьох модулів: з дванадцяти правил, заявлених «гейт», ДЕВ'ЯТЬ блокували образ,
# не маючи під собою ЖОДНОЇ константи з тіром (K-EYE-01, K-GLV-01, K-HAT-01,
# K-SIZ-01, K-WEA-05, K-WEA-06, K-OUT-05, K-OUT-15, K-OUT-41). `_обмежити_тіром`
# їх не чіпав: без константи стеля — None, а None нічого не знижує.
# ЩО СТАЛО: гейт видається лише тоді, коли доказова база під правилом ОГОЛОШЕНА
# і дозволяє hard/strong. Нема константи — нема гейта, і знахідка каже це вголос
# полем `гейт_знято` (мовчазне зняття було б тим самим дефектом навпаки).
ГЕЙТ_БЕЗ_ДОКАЗУ = ("регістр «гейт» заявлено, але під правилом не оголошено жодної "
                   "константи з тіром — доказової бази нема, тож гейт не видається")


def _гейт_без_доказу(правило, сила, reg=None):
    """Чи саме БРАК доказової бази зняв гейт із цієї знахідки.
    Слабка сила під гейтом — інша причина (вона була й до Н-V23-046), і плутати
    їх не можна: «нічим судити» і «судили й вийшло слабко» — різні стани.
    Гейт на МЕЖІ ЛЮДИНИ доказової бази в реєстрі констант не потребує (див.
    `ПОЛІТИКА_ДОК`), тож і зняти його браком тіру не можна."""
    if сила == "питання": return False
    п = _політика(правило)
    if п.get("регістр") != "гейт" or п.get("підстава") == МЕЖА_ЛЮДИНИ: return False
    # ГЕЙТ ВІД КОРПУСУ БРАКОМ ТІРУ НЕ ЗНІМАЄТЬСЯ (19.09.2026). `регістр()` з 16.09
    # видає гейт уже на самій силі корпусу («FORCE: hard» — цього досить), і без
    # цього рядка знахідка вийшла б із блокує=True І з полем `гейт_знято`, тобто
    # сказала б про себе дві протилежні речі. Брак константи з тіром тут не
    # умовчання, а факт про правило: вето категорійне (слово складу), порога нема.
    if п.get("сила_корпусу") in ("hard", "strong"): return False
    return сила in ("hard", "strong") and стеля_сили(правило, reg) is None


def регістр(правило, сила, reg=None):
    """Регістр знахідки — ЄДИНА функція, що його вирішує, з ЄДИНОЇ таблиці.

    `рег_карту` (чужу карту в параметрі) знято Н-02-05: доти кожен викликач мав
    право підсунути свою, і політика розійшлась на шість карт плюс два прямі
    переписування результату. Лишився `reg` — реєстр КОНСТАНТ модуля, з якого
    прийшла знахідка: без нього стеля тіру рахувалась би по REGISTRY ядра, і
    правило accessory/outer щоразу виглядало б беззаконним."""
    # РЕГІСТР БУВ СУТО ПО-ПРАВИЛЬНИЙ, і це втрачало один випадок: правило працює, а
    # ВХОДУ під конкретну річ немає. «Питання» — властивість ВИКЛИКУ, не правила:
    # K-BOD-02 має вхід на полотні й не має його, коли тканина не відома. Доти таке
    # спрацювання виходило реплікою, тобто НЕВІДРІЗНЯЛЬНО від виміряного вердикту, і
    # стиліст не бачив, що під ним бракує входу. Сила «питання» тепер сама себе несе.
    if сила == "питання": return "питання"
    п = _політика(правило)
    р = п.get("регістр", "репліка")
    # СИЛА КОРПУСУ — ДОСТАТНЯ ПІДСТАВА ДЛЯ ГЕЙТА (16.09.2026). Доти корпусне `hard`
    # без константи тіру виходило реплікою («гейт без оголошеного тіру»), і
    # «тип "джинси" не належить до коду business_casual» силою 0.95 нікого не
    # зупиняло: образ ішов у вибір із `перевірено: True`. Корпус каже «FORCE: hard
    # where a code is stated» — цього досить.
    if п.get("сила_корпусу") in ("hard", "strong") and сила in ("hard", "strong"):
        return "гейт"
    if р != "гейт": return р
    # МЕЖА ЛЮДИНИ: доказ — те, що людина це сказала (тема-4:658). Тір не питається,
    # інакше особисте вето втратило б силу рівно там, де корпус її не вимагає.
    if п.get("підстава") == МЕЖА_ЛЮДИНИ: return "гейт"
    if сила in ("hard", "strong") and стеля_сили(правило, reg) in ("hard", "strong"):
        return "гейт"
    return "репліка"      # слабка знахідка навіть механічного правила лише промовляється
