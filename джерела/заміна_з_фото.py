# -*- coding: utf-8 -*-
"""Заміна з фото: вибір моделі у пулі руки, перевірений спільним джерелом.

Фото може виявити інший колір, рід чи недоречність. Кандидати того самого слота
проходять повний суд із відповідністю учасників; нове або перенесене зауваження
відхиляє заміну. Прийняття повторює той самий контракт і не змінює її вибору.
"""
import внутрішня_мова as _ВМ
import повнота_образу as _ПО
import протокол as _ПР
import пропозиція_заміни as _ПЗ
import уважний_вибір as _УВ

# ПІДСТАВИ ЗАМІНИ — закритий перелік кодів (аудит/ПРОДУКТ.md п.12): модель каже код, код його лише звіряє;
# перелік — у схемі відповіді опису (`протокол.ПІДСТАВИ_ЗАМІНИ`), тут — що кожна значить.
#   colour   — фото показує явно інший колір, ніж той, що знає код;
#   kind     — на фото інший рід речі (не джемпер, а кардиган; не туфлі, а босоніжки);
#   occasion — річ на фото недоречна для її нагоди (матеріал, фасон, вигляд);
#   day      — річ на фото не для її погоди чи дороги («day»: тонка висока шпилька на сніг і двадцять хвилин
#              пішки, тонкий підбор на траву церемонії). Висоти й виду каблука, підошви в записі речі нема
#              (K-WEA-06: зчеплення з фото «наявним кодом не витягається — потрібен VLM»), тож це бачить лише
#              модель з фото. Доти підстави не було, і опис визнавав річ не для дня й лишав її (живий-як-людина-3,
#              с8 і с5): «з поясненням — свідомий вибір» (п.17) діє, коли та, що обирала, знала про річ те, що на
#              фото, а складання й ремонт фото не бачать.
ПІДСТАВИ = _ПР.ПІДСТАВИ_ЗАМІНИ
# Підстава «day» несе ще й факти її дня: без них «чого бракує» не каже, для якого дня потрібна річ.
ДЕНЬ = "day"
# Відмова, за якої картка не каже, чого бракує: річ не в образі — нема про що; її річ — її вибір (п.9), і рядок
# «бракує речі цього роду» радив би замінити те, що вона сама принесла.
БЕЗ_РЯДКА = ("item_not_in_outfit", "her_own_item")
# Скільки запасних іде в другий виклик з фото: кожна — це кадр у запиті; трьох досить для вибору,
# а стеля API в 20 зображень не мусить зрізати кадрів самого образу.
ЗАПАСНИХ_МАКС = 3
# Скільки кандидатів код пробує суддею: кожна проба — суд цілого образу. Вісім покриває інші образи
# руки (до чотирьох речей того самого слота) і перші місця пулу.
ПРОБ_МАКС = 8


def _перевірена(склад, нові, словник, кандидати, суддя):
    """Судить фото-вибір спільним джерелом у межах пулу та закріплених речей."""
    межі = {str(р["id"]): словник[str(р["id"])]
            for пул in кандидати.values() for р in пул if str(р["id"]) in словник}
    явний = [і for і in склад if _УВ.свої(словник.get(і)) or (словник.get(і) or {}).get("її_річ")]
    перевірка = _ПЗ.перевірити_ід(склад, нові, словник, межі, явний, суддя)
    if перевірка.get("образ") is None:
        return None
    if _ПО.чому_не_можна(перевірка["вердикт"]):
        return None
    return перевірка


def _кандидати_слота(слот, склад, річ, інші_образи, кандидати, словник):
    """Порядок проби: речі слота з інших фінальних образів руки (у порядку образів), далі пул слота."""
    вих = []
    for о in (інші_образи or []):
        for і in (о or []):
            і = str(і)
            if (словник.get(і) or {}).get("слот") == слот and і not in склад and і != річ and і not in вих:
                вих.append(і)
    for r in ((кандидати or {}).get(слот) or []):
        і = str(r.get("id") or "")
        if і and і not in склад and і != річ and і not in вих and not r.get("власна"):
            вих.append(і)
    return вих


def запасні(заміна, склад, частини, інші_образи, кандидати, словник, номери, суддя, день=None):
    """Крок 2: названа річ → запасні того самого слота, які пройшли суд на її місці.

    → `{стан, річ, чому, слот, запасні: [{id, н, вердикт}], відкинуто: [{id, чому}], текст}`; `стан`:
    `spares` (є що показати моделі), `no_spares`, `refused` (`відмова` каже чому: номер речі не прочитано,
    річ не в образі, її річ, половина комплекту, підстава поза переліком, слот невідомий). `текст` — рядок
    картки про склад, який код вирішив (`текст_складу`); на `spares` — той, що піде, коли заміни не буде.
    `день` — її день кодами (`сценарій.день_кодами`)."""
    річ, чому = str((заміна or {}).get("річ") or ""), (заміна or {}).get("чому")
    з = dict(річ=річ, чому=чому, запасні=[], відкинуто=[])
    запис = словник.get(річ) or {}
    відмова = ((заміна or {}).get("відмова") or
               ("item_not_in_outfit" if річ not in склад else
                "reason_not_in_list" if чому not in ПІДСТАВИ else
                "her_own_item" if запис.get("власна") or запис.get("її_річ") else
                "set_half" if (частини or {}).get(річ) else
                "slot_unknown" if not запис.get("слот") else None))
    if відмова:
        р = dict(з, стан="refused", відмова=відмова)
        return dict(р, текст=текст_складу(р, склад, словник, день))
    з["слот"] = запис["слот"]
    for і in _кандидати_слота(з["слот"], склад, річ, інші_образи, кандидати, словник)[:ПРОБ_МАКС]:
        нові = [і if х == річ else х for х in склад]
        перевірка = _перевірена(склад, нові, словник, кандидати, суддя)
        if перевірка is None:
            з["відкинуто"].append(dict(id=і, чому="replacement_not_verified"))
            continue
        з["запасні"].append(dict(id=і, н=(номери or {}).get(і) or і, вердикт=перевірка["вердикт"]))
        if len(з["запасні"]) >= ЗАПАСНИХ_МАКС:
            break
    р = dict(з, стан="spares") if з["запасні"] else dict(з, стан="no_spares")
    return dict(р, текст=текст_складу(р, склад, словник, день))


def вирішити(заміна_моделі, запит, склад, суддя, словник, кандидати, день=None):
    """Крок 3: відповідь опису з фото запасних → рішення коду про склад картки.

    `запит` — що код показав моделі (`{річ, чому, запасні: [id]}`), `заміна_моделі` — її `заміна`
    (`на` — id обраної запасної або None; відповідь без `swap` — порожня). → `{стан, річ, на?, чому, ід?,
    відмова?, текст}`: `accepted` — склад `ід` іде на картку; `kept` — модель лишила річ; `refused` — номер не
    прочитано, обрана не з запропонованих або склад не пройшов повторну перевірку. `текст` — рядок картки про
    склад, який код вирішив (`текст_складу`)."""
    річ = str((запит or {}).get("річ") or "")
    пропоновано = [str(і) for і in ((запит or {}).get("запасні") or [])]
    на = (заміна_моделі or {}).get("на")
    з = dict(річ=річ, чому=(запит or {}).get("чому"), пропоновано=пропоновано)
    if (заміна_моделі or {}).get("відмова"):
        р = dict(з, стан="refused", відмова=заміна_моделі["відмова"])
        return dict(р, текст=текст_складу(р, склад, словник, день))
    if not на:
        р = dict(з, стан="kept")
        return dict(р, текст=текст_складу(р, склад, словник, день))
    на = str(на)
    if на not in пропоновано or річ not in склад:
        р = dict(з, стан="refused", на=на, відмова="not_offered" if на not in пропоновано
                 else "item_not_in_outfit")
        return dict(р, текст=текст_складу(р, склад, словник, день))
    нові = [на if х == річ else х for х in склад]
    перевірка = _перевірена(склад, нові, словник, кандидати, суддя)
    if перевірка is None:
        р = dict(з, стан="refused", на=на, відмова="replacement_not_verified")
        return dict(р, текст=текст_складу(р, склад, словник, день))
    р = dict(з, стан="accepted", на=на, ід=нові)
    return dict(р, вердикт=перевірка["вердикт"], текст=текст_складу(р, склад, словник, день))


def текст_складу(рішення, склад, словник, день=None):
    """ПИСАР ТЕКСТУ СКЛАДУ, ЯКИЙ КОД ВИРІШИВ (корінь Е3-заміна-з-перевіркою, умова «г»): рядок картки
    внутрішньою мовою (п.12) про образ, що на картці, — одне місце для кожного рішення про заміну з фото.

    Опис, що запропонував заміну, писав образ, якого може й не бути: на картку його проза не йде
    (`показ/збирання_руки.js`, «ТЕКСТ КАРТКИ — ДЛЯ СКЛАДУ, ЯКИЙ КОД ВИРІШИВ»), опис пишеться наново для
    вирішеного складу, а цей рядок каже жінці те, чого опис не каже: `accepted` — що стилістка замінила й чому;
    будь-яке інше рішення (відмова, нема запасної, лишила річ, виклик упав) — річ лишилась, що фото показало і
    чого образу бракує для її нагоди (п.17: заміни нема — пояснення). Доти так було лише для підстави `day`,
    решта рішень лишала на картці прозу з оголошенням заміни. Без рядка — коли річ не в образі, підстава не з
    переліку (що бракує, невідомо) чи це її річ (`БЕЗ_РЯДКА`)."""
    р = рішення or {}
    річ, чому = str(р.get("річ") or ""), р.get("чому")
    if р.get("стан") == "accepted":
        return повідомлення(річ, str(р.get("на")), чому, словник)
    if річ not in (склад or ()) or чому not in ПІДСТАВИ or р.get("відмова") in БЕЗ_РЯДКА:
        return None
    if (словник.get(річ) or {}).get("власна") or (словник.get(річ) or {}).get("її_річ"):
        return None
    return бракує(річ, чому, словник, день)


def повідомлення(річ, на, чому, словник):
    """Рядок картки внутрішньою мовою (п.12): що стилістка замінила, побачивши фото, і чому.
    Назви — ті, що жінка бачить у списку речей (`повнота_образу.назва_коротко`).
    ПІДСТАВА «ІНШИЙ РІД» ПРИ ЗАМІНІ ТИМ САМИМ ТИПОМ — НЕ ЗАЯВА: «на знімку лофери
    виявилися іншого виду — я замінила їх такими ж бежевими лоферами»: `kind`, а нова річ того самого `тип`
    каталогу, — речення суперечить собі. Тоді підстава — «невідомо»; код моделі (`чому`) лишається в записі заміни."""
    тип = lambda і: (словник.get(і) or {}).get("тип")
    if чому == "kind" and тип(річ) and тип(річ) == тип(на):
        чому = None
    return _ВМ.повідомлення("card_item_swapped", _ВМ.заява(
        "stylist_swapped_item_after_photo",
        # річ — кодами за записом словника, без назви (Е2-вхід-опису-кодами)
        was=_ВМ.річ_заяви(dict(словник.get(річ) or {}, id=річ)),
        now=_ВМ.річ_заяви(dict(словник.get(на) or {}, id=на)),
        reason=(чому if чому in ПІДСТАВИ else _ВМ.UNKNOWN)))


def бракує(річ, чому, словник, день=None):
    """Рядок картки внутрішньою мовою (п.12): фото речі показало підставу `чому` (колір, рід, нагода, день), а
    заміни на картці нема — річ лишилась, і бракує речі цього роду без тієї вади. День — лише для підстави
    `day` і лише відомі факти кодами (`сценарій.день_кодами`); невідомого не вигадуємо."""
    д = {к: v for к, v in ((день or {}) if чому == ДЕНЬ else {}).items()
         if к in ("weather_band", "precipitation", "movement", "surface", "activity", "setting") and v}
    return _ВМ.повідомлення("card_incomplete", _ВМ.заява(
        "photo_item_unfit_no_swap", item=_ВМ.річ_заяви(dict(словник.get(річ) or {}, id=річ)), reason=чому, **д))
