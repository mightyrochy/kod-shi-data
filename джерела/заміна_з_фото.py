# -*- coding: utf-8 -*-
"""заміна_з_фото.py — крок опису з фото може замінити ОДНУ річ (ФОТО-1, рішення власника 02.10.2026).

РІШЕННЯ ВЛАСНИКА (CLAUDE.md п.17): «Останній крок із фото може замінити річ — так, якщо після всіх
перевірок і запобіжників на це все ще є вагома причина.»

ЯК БУЛО. Образи складаються без фото речей; фото бачить лише останній крок — опис, і правило
промпта казало йому «Do not change the outfit». Коли фото суперечило коду (рядок 757: назва й
слово крамниці «білий джемпер», а кадр — хакі), опис міг лише написати про це словами, і жінка
діставала річ, якої в задумі образу не було.

ЯК СТАЛО — ДВА КРОКИ, І РІШЕННЯ НА КОЖНОМУ КАЖЕ КОД.
  1. Опис (виклик, що був і доти) може назвати в полі `заміна` ОДНУ річ і ПІДСТАВУ кодом (`ПІДСТАВИ`):
     фото показує явно інший колір, інший рід речі або річ, недоречну для її нагоди. Без вагомої
     причини поле порожнє — і нічого більше не відбувається: ні виклику, ні затримки.
  2. Код (`запасні`) шукає речі ТОГО САМОГО слота — спершу з інших фінальних образів руки (їх уже
     обрала стилістка), далі з пулу руки в його порядку — і кожну пробує на місці названої тим самим
     суддею, що судить образи моделі (`міст_відповіді._суддя`): структура без блокера, жодного
     невідремонтованого гейта, жодної НОВОЇ сильної знахідки проти образу як він є (`перевірити_склад`).
     Лише кандидати, що пройшли, ідуть далі (до `ЗАПАСНИХ_МАКС`). Нема жодного — заміни нема.
  3. Лише тоді — один зайвий виклик: той самий опис, де поруч з образом стоять запасні з ФОТО. Модель
     обирає одну (`заміна.на`) або лишає річ. Код звіряє: обрана — з запропонованих, склад ще раз
     проходить ту саму перевірку; тоді образ картки — новий, і картка каже жінці, що замінено й чому
     (`повідомлення`, речення складає мовний шар).

ЧОГО ЦЕ НЕ РОБИТЬ, І ЦЕ НАВМИСНО: не міняє більше однієї речі; не міняє її річ з фото (`її_річ`) і
половину комплекту (комплект — дві речі однією покупкою, одна заміна його ламає); не шукає поза
пулом руки. Кожна відмова має код (`стан`, `чому`) — у звіт власника, не мовчки.
"""
import внутрішня_мова as _ВМ

# ПІДСТАВИ ЗАМІНИ — закритий перелік кодів (CLAUDE.md п.12): модель каже код, код його лише звіряє.
#   colour   — фото показує явно інший колір, ніж той, що знає код;
#   kind     — на фото інший рід речі (не джемпер, а кардиган; не туфлі, а босоніжки);
#   occasion — річ на фото недоречна для її нагоди (матеріал, фасон, вигляд).
ПІДСТАВИ = ("colour", "kind", "occasion")
# Скільки запасних іде в другий виклик з фото: кожна — це кадр у запиті; трьох досить для вибору,
# а стеля API в 20 зображень не мусить зрізати кадрів самого образу.
ЗАПАСНИХ_МАКС = 3
# Скільки кандидатів код пробує суддею: кожна проба — суд цілого образу. Вісім покриває інші образи
# руки (до чотирьох речей того самого слота) і перші місця пулу.
ПРОБ_МАКС = 8
# Сила знахідки, нова поява якої відкидає заміну: те, що код уже вважає сильним аргументом проти образу.
СИЛЬНІ = ("hard", "strong")


def _сильні(к):
    """Правила сильних несвідомих знахідок образу вердикта (`сила` hard/strong)."""
    return {str(z.get("правило")) for z in ((к or {}).get("знахідки") or [])
            if isinstance(z, dict) and z.get("сила") in СИЛЬНІ and not z.get("свідомий")}


def перевірити_склад(нові, суддя, база=None):
    """Склад після заміни крізь ТОГО САМОГО суддю, що й образи моделі → (чому_ні | None, образ_вердикта).

    `суддя` — `міст_відповіді._суддя` (набори → образи ВЕРДИКТ_V1); `база` — образ вердикта складу як
    він є. Відмова: суд упав; структурний блокер чи невідремонтований гейт (`повнота_образу._чому_не_можна`
    — та сама межа, з якою образ іде на картку); нова сильна знахідка, якої в образі не було."""
    import повнота_образу as _ПО
    к = (суддя([list(нові)]) or [None])[0]
    if not isinstance(к, dict):
        return "judge_failed", None
    чому = _ПО._чому_не_можна(к)
    if чому:
        return чому, к
    нові_сильні = sorted(_сильні(к) - _сильні(база)) if база is not None else []
    if нові_сильні:
        return "new_strong_finding=" + ",".join(нові_сильні[:3]), к
    return None, к


def _кандидати_слота(слот, склад, річ, інші_образи, кандидати, словник):
    """Порядок проби: речі слота з інших фінальних образів руки (у порядку образів), далі пул слота."""
    вих = []
    for о in (інші_образи or []):
        for і in (о or []):
            і = str(і)
            if (словник.get(і) or {}).get("слот") == слот and і not in склад and і != річ and і not in вих:
                вих.append(і)
    for r in ((кандидати or {}).get(слот) or []):
        і = str(r.get("id") or "")
        if і and і not in склад and і != річ and і not in вих and not r.get("власна"):
            вих.append(і)
    return вих


def запасні(заміна, склад, частини, інші_образи, кандидати, словник, номери, суддя):
    """Крок 2: названа річ → запасні того самого слота, які пройшли суд на її місці.

    → `{стан, річ, чому, слот, запасні: [{id, н}], відкинуто: [{id, чому}], база?}`; `стан`:
    `spares` (є що показати моделі), `no_spares`, `refused` (`відмова` каже чому: річ не в образі,
    її річ, половина комплекту, підстава поза переліком, суд образу як він є впав)."""
    річ, чому = str((заміна or {}).get("річ") or ""), (заміна or {}).get("чому")
    з = dict(річ=річ, чому=чому, запасні=[], відкинуто=[])
    запис = словник.get(річ) or {}
    відмова = ("item_not_in_outfit" if річ not in склад else
               "reason_not_in_list" if чому not in ПІДСТАВИ else
               "her_own_item" if запис.get("власна") or запис.get("її_річ") else
               "set_half" if (частини or {}).get(річ) else
               "slot_unknown" if not запис.get("слот") else None)
    if відмова:
        return dict(з, стан="refused", відмова=відмова)
    з["слот"] = запис["слот"]
    _ч, база = перевірити_склад(склад, суддя)
    if база is None:
        return dict(з, стан="refused", відмова="judge_failed_on_outfit")
    for і in _кандидати_слота(з["слот"], склад, річ, інші_образи, кандидати, словник)[:ПРОБ_МАКС]:
        нові = [і if х == річ else х for х in склад]
        ні, _к = перевірити_склад(нові, суддя, база=база)
        if ні:
            з["відкинуто"].append(dict(id=і, чому=ні))
            continue
        з["запасні"].append(dict(id=і, н=(номери or {}).get(і) or і))
        if len(з["запасні"]) >= ЗАПАСНИХ_МАКС:
            break
    з["стан"] = "spares" if з["запасні"] else "no_spares"
    return з


def вирішити(заміна_моделі, запит, склад, суддя, словник):
    """Крок 3: відповідь опису з фото запасних → рішення коду про склад картки.

    `запит` — що код показав моделі (`{річ, чому, запасні: [id]}`), `заміна_моделі` — її `заміна`
    (`на` — id обраної запасної або None). → `{стан, річ, на?, чому, ід?, повідомлення?, відмова?}`:
    `accepted` — склад `ід` іде на картку; `kept` — модель лишила річ; `refused` — обрана не з
    запропонованих або склад не пройшов повторну перевірку."""
    річ = str((запит or {}).get("річ") or "")
    пропоновано = [str(і) for і in ((запит or {}).get("запасні") or [])]
    на = (заміна_моделі or {}).get("на")
    з = dict(річ=річ, чому=(запит or {}).get("чому"), пропоновано=пропоновано)
    if not на:
        return dict(з, стан="kept")
    на = str(на)
    if на not in пропоновано or річ not in склад:
        return dict(з, стан="refused", на=на, відмова="not_offered" if на not in пропоновано
                    else "item_not_in_outfit")
    нові = [на if х == річ else х for х in склад]
    ні, _к = перевірити_склад(нові, суддя, база=перевірити_склад(склад, суддя)[1])
    if ні:
        return dict(з, стан="refused", на=на, відмова=ні)
    return dict(з, стан="accepted", на=на, ід=нові,
                повідомлення=повідомлення(річ, на, з["чому"], словник))


def повідомлення(річ, на, чому, словник):
    """Рядок картки внутрішньою мовою (п.12): що стилістка замінила, побачивши фото, і чому.
    Назви — ті, що жінка бачить у списку речей (`повнота_образу._назва_коротко`)."""
    import повнота_образу as _ПО
    return _ВМ.повідомлення("card_item_swapped", _ВМ.заява(
        "stylist_swapped_item_after_photo",
        was=_ВМ.вільний(_ПО._назва_коротко(річ, словник)),
        now=_ВМ.вільний(_ПО._назва_коротко(на, словник)),
        reason=(чому if чому in ПІДСТАВИ else _ВМ.UNKNOWN)))
