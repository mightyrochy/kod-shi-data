"""її_входи.py — що продукт справді питає в неї про неї саму: одне джерело для тексту правил.

ЧОМУ ЦЕЙ ФАЙЛ ІСНУЄ (корінь Е2-текст-жінці, вада 10 живих «як людина» 13.11–14.11, рядок дошки 15409).
Правила, яким бракує її виміру, писали, ДЕ його взяти, вільним рядком у своєму файлі: «одне питання
анкети: скільки пар у вас є» (`аксесуари_структура`, K-EYE-03), «питання анкети: скільки пар окулярів»
(`аксесуари_реєстр`), «анкета коштує хвилину на вимір» (`аксесуари_розмір`), опис заяви «she can enter
it herself: tab "Profile", row "Extended measurements"…» (`внутрішня_мова`). Анкети в продукті нема,
а поле профілю є лише для шести вимірів «Розширених вимірів» (`показ.html`, розкривач `мр-розширені`);
кількості пар окулярів, міжзіницевої, зап'ястя чи долоні продукт у неї не питає. Кожен рядок
складався окремо й відставав від екрана сам: заява про стопу казала «анкета», коли поле вже стояло
в профілі, а K-EYE-03 обіцяв питання, якого екран не ставить.

ЩО ТЕПЕР. Поле профілю, яке вона заповнює сама, названо тут раз — ключем виміру (`fit.тіло`,
`fit.АКСЕСУАРНІ_ВИМІРИ`), написом поля й одиницею з `показ.html`. Текст правила про її вимір
(`ремонт`, опис заяви для моделі) складають функції нижче з цієї таблиці; ключ, якого тут нема,
дає «продукт у неї не питає», і заява про нього йде у звіт власника (`кому`), а не їй
(ПРОДУКТ п.9: входу, якого нема в системі, жінці не ставлять). Новий рядок поля з'являється тут
разом із полем на екрані: `тест_протоколу.py` звіряє написи й ідентифікатори з `показ.html`.
"""

# Розділ профілю, де стоять поля нижче: вкладка й рядок-розкривач (`показ.html`, `мр-розширені`).
РОЗДІЛ = dict(вкладка="Профіль", рядок="Розширені виміри")
РОЗДІЛ_EN = dict(вкладка="Profile", рядок="Extended measurements")

# ключ виміру → поле профілю: id поля в `показ.html`, напис на екрані, напис англійською для
# опису заяви (модель пише жінці українською сама), одиниця.
ПОЛЯ_ПРОФІЛЮ = {
    "високе_стегно":    dict(ід="мр-високе-стегно", поле="Високе стегно", field="High hip", одиниця="см", unit="cm"),
    "коліно":           dict(ід="мр-коліно", поле="Коліно", field="Knee", одиниця="см", unit="cm"),
    "литка":            dict(ід="мр-литка", поле="Литка", field="Calf", одиниця="см", unit="cm"),
    "щиколотка":        dict(ід="мр-щиколотка", поле="Щиколотка", field="Ankle", одиниця="см", unit="cm"),
    "довжина_стопи_мм": dict(ід="мр-стопа", поле="Довжина стопи", field="Foot length", одиниця="мм", unit="mm"),
    "голова_см":        dict(ід="мр-голова", поле="Обхват голови", field="Head girth", одиниця="см", unit="cm"),
}


def питає(ключ):
    """Чи продукт питає цей вимір у неї (є поле профілю, яке вона заповнює сама)."""
    return ключ in ПОЛЯ_ПРОФІЛЮ


def де_ввести(ключ):
    """Українською, для звіту власника й `ремонт` правила: «Профіль → Розширені виміри → Довжина стопи (мм)»."""
    п = ПОЛЯ_ПРОФІЛЮ[ключ]
    return "%s → %s → %s (%s)" % (РОЗДІЛ["вкладка"], РОЗДІЛ["рядок"], п["поле"], п["одиниця"])


def де_ввести_en(ключ):
    """Для опису заяви моделі: «tab "Profile", row "Extended measurements", field "Foot length" (mm)»."""
    п = ПОЛЯ_ПРОФІЛЮ[ключ]
    return 'tab "%s", row "%s", field "%s" (%s)' % (РОЗДІЛ_EN["вкладка"], РОЗДІЛ_EN["рядок"], п["field"], п["unit"])


def ремонт(ключ, що=None):
    """`ремонт` правила, якому бракує її виміру `ключ`: де вона введе його сама, а коли поля нема —
    що продукт цього в неї не питає (`що` — назва входу словами для звіту, без неї — ключ)."""
    if питає(ключ):
        return "її вимір: %s" % де_ввести(ключ)
    return "вхід «%s» продукт у неї не питає — поля нема" % (що or ключ)


def кому(ключ):
    """Адресат заяви «код не знає її <ключ>»: їй — лише коли вона може дати це сама в профілі;
    інакше — журнал (звіт власника). Повертає kwargs для `внутрішня_мова.заява`."""
    return {} if питає(ключ) else dict(recipient="journal")
