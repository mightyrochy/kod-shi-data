# -*- coding: utf-8 -*-
"""ГЕЙТ ПОКРИТТЯ ПЛОЩ: скільки речей живого фіду приходять до суду з ВИМІРЯНОЮ площею.

НАВІЩО ЦЕЙ ПРИЛАД (Н-outfit-1-081). Пʼять колірних правил — K-COL-01 (структура
світлоти), K-COL-02 (бюджет і конфлікт хром), K-COL-05 (сирота-акцент і matchy),
K-COL-06 (крос-нейтралі), K-COMP-03 (кількість сімей) — виносяться лише тоді, коли
площа кожної речі має НАЗВАНЕ походження (`джерело_площі`). Інакше `outfit.review`
утримує їх усі й каже це вголос. Рішення правильне: вигадана площа гірша за мовчання
(виміряно 08.09.2026 — заглушка 1/N одночасно додала три хибні знахідки і проковтнула
справжню). Але доти МОВЧАННЯ ПʼЯТИ ПРАВИЛ НІХТО НЕ МІРЯВ: покриття могло впасти з 80 %
до 0 % і жодне число в дереві цього не показало б, бо «утримано» виглядає однаково за
будь-якого покриття.

ЩО МІРЯЄ: частку речей живого фіду, яким `outfit.площі_з_геометрії` справді поставила
площу, і РОЗКЛАД `край_джерело` — тобто ПРИЧИНУ, чому покриття таке, а не інше.

КОД ВИХОДУ ЧЕСНИЙ: 1, коли покриття нульове (пʼять правил мовчать над усім фідом), 0 —
коли хоч одна річ доходить із виміряною площею. СЬОГОДНІ ЦЕ 1, І ЦЕ НЕ ПОЛОМКА ПРИЛАДА:
фід не несе довжин виробів, краї беруться зі слова або з дефолту слота, і площа з них —
та сама вигадка. Прилад зеленітиме тоді, коли в каталозі зʼявляться довжини (або коли
`areas` навчиться інтегрувати площу по ЗОНІ країв зі слова разом із її розкидом).
Цей прилад НЕ входить у ланцюжок гейтів §0 — він свідок стану даних, не тест коду.

Прогін:  python3 gate_площі.py            (офлайн, детермінований, ліміт_фото=0)
"""
import sys, os, json, collections

ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ТУТ)
# ПРИ ІМПОРТІ ПРИЛАД НІЧОГО НЕ РОБИТЬ (Н-00-07): ні `chdir`, ні прогону. Шляхи —
# абсолютні від теки модуля, бо гейт можна покликати з будь-якої теки.
_шлях = lambda і: os.path.join(ТУТ, і)

СЛОТИ = ("верх", "низ", "взуття", "сумка")

СЦЕНАРІЇ = {
    "офіс·18°C": dict(нагода="робота", місце="офіс", година=9, темп_c=18,
                      дрес_код="business_casual"),
    "дощ·ресторан·вечір": dict(нагода="побачення", місце="ресторан", година=20,
                               темп_c=5, опади="дощ", вітер=8, реагенти="так"),
}


def образ_фіду(назва, сцен):
    """Один образ живого шляху: кандидати з фіду → `composer._у_річ` → площі."""
    import bridge as B, composer as КМ, fit as ПС, outfit as O
    вх = json.load(open(_шлях("стенд_вх.json")))
    вх["сценарій"] = сцен
    вх["випадок"] = назва
    r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    if r.get("помилка"):
        return dict(помилка=r["помилка"])
    к = r.get("кандидати") or {}
    # річ береться з каталогу за id, а не з рядка для моделі: рядок для моделі не несе
    # ні геометрії, ні кольору (bridge.каталог_останнього_пакета це й пояснює)
    _кат = {x.get("id"): x for x in B.каталог_останнього_пакета()}
    речі = []
    for слот in СЛОТИ:
        пул = к.get(слот) or []
        if not пул:
            continue
        повна = _кат.get(пул[0].get("id"))
        речі.append(dict(повна or пул[0], слот=слот))
    if len(речі) < 2:
        return dict(помилка="замало кандидатів")
    T = ПС.тіло(float(вх["зріст"]), {k: float(v) for k, v in вх["обхвати"].items()})
    готові = [КМ._у_річ(dict(c), c["слот"], T) for c in речі]
    готові, звіт = O.площі_з_геометрії(готові, T)
    з_площею = [g for g in готові if g.get("джерело_площі")]
    return dict(речей=len(готові), з_площею=len(з_площею),
                покриття=round(len(з_площею) / len(готові), 3),
                край=collections.Counter(str(g.get("край_джерело")) for g in готові),
                звіт=звіт)


def main():
    # РОБОЧА ТЕКА СТАВИТЬСЯ ТУТ, А НЕ ПРИ ІМПОРТІ (Н-00-07): живий шлях дістає
    # каталог і кеші відносними шляхами, тож прилад мусить стояти в `джерела` —
    # але робити це імпортом означало б мовчки рухати теку будь-кому, хто модуль
    # лише читає.
    os.chdir(ТУТ)
    import outfit as O
    рядки, покриття = [], []
    for назва, сцен in СЦЕНАРІЇ.items():
        r = образ_фіду(назва, сцен)
        if r.get("помилка"):
            рядки.append("  %-22s ПОМИЛКА: %s" % (назва, r["помилка"]))
            continue
        покриття.append(r["покриття"])
        рядки.append("  %-22s речей %d · з виміряною площею %d · покриття %.0f %%"
                     % (назва, r["речей"], r["з_площею"], r["покриття"] * 100))
        рядки.append("      край_джерело: %s"
                     % ", ".join("%s×%d" % (k, v) for k, v in sorted(r["край"].items())))
        рядки.append("      чому: %s" % r["звіт"]["чому"])
    print("ПОКРИТТЯ ПЛОЩ НА ЖИВОМУ ФІДІ")
    print("\n".join(рядки))
    print("\nутримуються без площ: %s" % "; ".join(O.ПЛОЩОЗАЛЕЖНІ))
    if not покриття:
        print("БЕЗ ВХОДУ: жоден сценарій не зібрав образу — покриття не поміряне")
        return 1
    сер = sum(покриття) / len(покриття)
    print("СЕРЕДНЄ ПОКРИТТЯ: %.0f %% по %d образах" % (сер * 100, len(покриття)))
    # ЧОМУ ПОРІГ РІВНО НУЛЬ, А НЕ «мало»: будь-яке ненульове покриття означає, що шлях
    # від виміру до правила ПРОХОДИТЬ, і далі питання даних, не коду. Нуль означає, що
    # пʼять правил не виносяться НІ РАЗУ — і це вже не утримання, а відсутній шар.
    if сер <= 0.0:
        print("ВПАЛО: покриття нульове — пʼять колірних правил мовчать над усім фідом. "
              "Причина в розкладі `край_джерело` вище: площа рахується лише з краю, "
              "що є виміром (outfit.КРАЙ_ДЖЕРЕЛО)")
        return 1
    print("ПРОЙДЕНО: шлях вимір → площа → правило проходить")
    return 0


if __name__ == "__main__":
    sys.exit(main())
