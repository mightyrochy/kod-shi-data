def узгодити_колір(колір, рід):
    """Кольороназву — за родом і числом речі: «чорний» + ж → «чорна», + мн → «чорні».

    Слово, яке не є прикметником («молоко», «хакі», «беж», «айворі»), лишається
    як є — саме так його пишуть і самі крамниці («Атласна сукня молоко»).

    ТРИ РІШЕННЯ, УСІ ЧЕРЕЗ ОДИН ЛЕКСИКОН (`verify.слово_крамниці`, той самий, що
    судить колір речі — свого словника тут не заводимо):
      · слово, якого лексикон не знає, — НЕ КОЛІР («принт», «смужка», «джинс»);
        порожньо, і назва лишається без дописки. «Сукня принт» кольору не називає;
      · слово крамниці чужою мовою («Beige», «черный») береться лексиконом
        українською: інакше англійська назва мінялась би на англійський колір
        («Dress Podyh Beige» → «Сукня beige», fromus → «Футболка черный»);
      · слово крамниці УКРАЇНСЬКОЮ лишається її словом (рішення власника 20.09,
        рядок 135: «якщо модель і магазини називають його бежевим, значить він
        бежевий») — «айворі» не стає «молочним»."""
    слово = str(колір or "").strip().split(",")[0].strip().split()[0].strip().lower() if колір else ""
    # Крамниця пише в полі кольору ще й мотив: wearme «сірий[ялинка]»,
    # «блакитний[горох]». Мотив — окреме поле речі (`візерунок`), і в назві
    # кольору йому не місце: лишаємо самі літери першого слова.
    слово = _re.match(r"[a-zа-яіїєґ'’\-]*", слово).group(0)
    if слово:
        import verify as _V
        ім = (_V.слово_крамниці(слово) or {}).get("ім")
        if not ім:
            return ""
        import language_gate as _LG
        if _re.search(r"[a-z]", слово) or _LG.російське(слово):
            слово = ім
    if not слово or рід == "ч":
        return слово
    for кін, форми in _ЗАКІНЧЕННЯ.items():
        if слово.endswith(кін) and len(слово) > len(кін) + 1:
            return слово[:-len(кін)] + форми[рід]
    return слово


def скласти(тип=None, слот=None, колір=None, довжина=None):
    """Назва з даних коду: «Сукня міді чорна», «Черевики коричневі». None — коли й слота нема."""
    пара = ТИП_НАЗВА.get(str(тип or "").strip().lower()) or СЛОТ_НАЗВА.get(str(слот or "").strip().lower())
    if not пара:
        return None
    іменник, рід = пара
    частини = [іменник]
    д = ДОВЖИНА_СЛОВОМ.get(str(довжина or "").strip().lower())
    if д and str(тип or "").strip().lower() in ДОВЖИНА_ДЛЯ:
        частини.append(д)
    к = узгодити_колір(колір, рід)
    if к and к not in іменник.lower():
        частини.append(к)
    return " ".join(частини)


# ── НАЗВА З ОПИСУ ПЕРЕД БРЕНДОМ У ДУЖКАХ ─────────────────────────────────────
# Картка brenda влаштована так: `<name>` — сам бренд («Max Mara»), а справжня
# назва стоїть першим рядком опису й закінчується тим самим брендом у дужках:
# «… УМОВИ ПОВЕРНЕННЯ Сарафан вільного крою (Max Mara) Склад: …». Вимір
# 23.09.2026: 126 зі 128 латинських назв brenda дістаються саме так.
_ХЛАМ_ОПИСУ = _re.compile(r"^.*(доставка і оплата|умови повернення|характеристики|"
                          r"відгуки|новий відгук або коментар|опис)\s*", _re.I)


def з_опису(назва, опис):
    """Фраза опису перед «(<назва>)» — коли `<name>` крамниці є лише брендом. Або None."""
    бренд = str(назва or "").strip()
    if not бренд or len(бренд) > 40:
        return None
    # ВІКНО {3,200} І ПОЧАТОК СЛОВА (рядок 182, 24.09.2026). Було {3,140} без
    # межі слова, і фраза, довша за вікно, починалась ПОСЕРЕД СЛОВА: brenda
    # ж-01594 «Сукня з відрізною лінією таліі, паском, … декор-камінці» — 146
    # символів, і на картку їхало «Укня з відрізною лінією таліі, паском…».
    # Коштувало це не лише слова: рядок 182 класифікує річ назвою картки, і
    # «Укня» без свого іменника віддавала слот «пояс» — сукня йшла з пулу сукень.
    # `(?<![^\W\d_])` — «перед початком фрази нема літери»: вікно тепер або бере
    # фразу цілою, або не бере зовсім, а не гризе перше слово.
    м = _re.search(r"(?<![^\W\d_])([^.!?;]{3,200}?)\s*\(%s\)" % _re.escape(бренд),
                   str(опис or ""))
    if not м:
        return None
    фраза = _ХЛАМ_ОПИСУ.sub("", м.group(1).strip()).strip(" ,·|-–—")
    # Бренд повертається на місце: у brenda `<name>` — це він, і картка без
    # нього втратила б те єдине, що крамниця про річ сказала прямо.
    return ("%s (%s)" % (фраза, бренд)) if фраза else None


# ═══════════════ 4. НАЗВА З КАРТКИ КРАМНИЦІ ═══════════════
# `назви_карток.json.gz` — {url картки: назва картки}, зібране з сирих жнив
# (`сирі/*.jsonl.gz`, поле `картка.назва`) скриптом `назви_карток_зібрати.py`.
# ЧОМУ ОКРЕМИЙ ФАЙЛ, А НЕ ПРАВКА ФІДУ: фід — зовнішній контракт, його пише
# магазин; правка `<name>` у ньому посунула б слот, ключ моделі й `тип_речі`
# (див. шапку). Файл лягає у вантаж поруч зі збагаченням і читається так само.
НАЗВИ_КАРТОК_ІМ = "назви_карток.json"
_КАРТКИ_КЕШ = {}


def читати_назви_карток(тека=None):
    """{url: назва з картки крамниці} — або порожньо, коли файла нема (тоді джерело просто мовчить)."""
    import os as _os
    тека = тека or _os.path.dirname(_os.path.abspath(__file__)) or "."
    for ш in (_os.path.join(тека, НАЗВИ_КАРТОК_ІМ), _os.path.join(тека, НАЗВИ_КАРТОК_ІМ + ".gz")):
        if not _os.path.exists(ш):
            continue
        ключ = (ш, _os.path.getmtime(ш))
        if ключ not in _КАРТКИ_КЕШ:
            import gzip as _gz, json as _json
            with (_gz.open(ш, "rt", encoding="utf-8") if ш.endswith(".gz")
                  else open(ш, encoding="utf-8")) as f:
                _КАРТКИ_КЕШ.clear()
                _КАРТКИ_КЕШ[ключ] = _json.load(f)
        return _КАРТКИ_КЕШ[ключ]
    return {}


# Мовна сестра сторінки: `ricamare.com.ua/ru/…` ↔ `ricamare.com.ua/…`,
# `kasandra.ua/en/…` ↔ `kasandra.ua/…`, `vilni.store/en/…` ↔ `vilni.store/…`.
# Так крамниця САМА переклала назву своєї речі — і це єдиний переклад, який тут
# дозволено: код українських слів не вигадує (вимога рядка 144).
_МОВНИЙ_СЕГМЕНТ = _re.compile(r"^(https?://[^/]+)/(?:ru|en|rus|eng)/", _re.I)


def сторінки_речі(url):
    """URL речі та її мовних сестер — у порядку, в якому їх варто питати."""
    u = str(url or "").strip()
    if not u:
        return []
    сестра = _МОВНИЙ_СЕГМЕНТ.sub(r"\1/", u)
    return [u] if сестра == u else [u, сестра]


# ═══════════════ 5. ВХІД: одна річ → назва для показу ═══════════════
# ── НАЗВА, ЯКА НЕ РОЗРІЗНЯЄ РЕЧЕЙ (вимір 23.09.2026) ────────────────────────
# Коли службовий код зрізано, від назви часом лишається сам іменник: vittorossi
# «Уги VS000086111» → «Уги», fromus «Футболка 2477-39» → «Футболка»,
# favoriteshoes «LeBERDES Лофери 000000019361» → «LeBERDES Лофери». На аркуші
# власника дванадцять «Футболок» підряд — це не назва, а слот. Колір крамниці
# тут і є та єдина ознака, яку код ЗНАЄ про річ, і вона вже судиться всім
# колірним шаром. Додаємо лише до назв у два слова й лише коли слова кольору в
# назві ще нема: довша назва вже щось розрізняє, і дописувати їй нічого.
СТЕЛЯ_СЛІВ_БЕЗ_КОЛЬОРУ = 2


# Іменник речі → його власний рід і число. Зібрано з тих самих двох таблиць,
# якими складається назва, — щоб слово й рід не розʼїхались мовчки.
_РІД_ІМЕННИКА = {і.split()[-1].lower(): р
                 for і, р in list(ТИП_НАЗВА.values()) + list(СЛОТ_НАЗВА.values())}


def рід_назви(назва, запасний):
    """Рід і число речі за словами самої назви; `запасний` — коли жодне слово не каже.

    ДВА КРОКИ, І ПОРЯДОК ВАЖИТЬ (вимір 23.09.2026):
      1. ІМЕННИК РЕЧІ, ЯКИЙ У НАЗВІ СТОЇТЬ, знає свій рід САМ, і шукається він
         з ПОЧАТКУ: «Сукня оверсайз» — це сукня, а не «оверсайз», і колір їй
         «чорнА» (wearme, 93 записи). Брати рід із `тип` теж не можна: sezone
         оголошує «тип=сукня» на «Лляний комбінезон» — вийшло б «комбінезон чорнА».
      2. Іменника з таблиці нема — рід за закінченням останнього слова: тип каже
         «взуття» (середній), а крамниця пише «Уги», і колір мусить бути «сірі».
    Слова довжини пропускаються обома кроками: «Сукня міді» закінчується на «і»,
    і за закінченням це була б множина («Сукня міді коричневІ»)."""
    слова = [w.lower().strip("«»\"'()") for w in str(назва or "").split()
             if w.lower().strip("«»\"'()") not in ДОВЖИНА_СЛОВОМ]
    for w in слова:
        власний = _РІД_ІМЕННИКА.get(w)
        if власний:
            return власний
    # Останнє слово КИРИЛИЦЕЮ, не просто останнє: «Каблучка Swell» закінчується
    # латинською назвою моделі, за якою роду не видно, і колір ставав «срібнИЙ»
    # при жіночому іменнику (jecomestudio).
    кирилиця = [w for w in слова if _re.search(r"[а-яіїєґ]", w)]
    слово = кирилиця[-1] if кирилиця else ""
    if not слово:
        return запасний
    if слово.endswith(("и", "і", "ї")):
        return "мн"
    if слово.endswith(("а", "я")):
        return "ж"
    if слово.endswith(("о", "е")):
        return "с"
    return "ч"


def доповнити_кольором(назва, тип, слот, колір):
    """До назви з самого іменника речі — слово кольору, узгоджене за родом. Інакше як є."""
    н = str(назва or "").strip()
    пара = ТИП_НАЗВА.get(str(тип or "").strip().lower()) or СЛОТ_НАЗВА.get(str(слот or "").strip().lower())
    if not пара or len(н.split()) > СТЕЛЯ_СЛІВ_БЕЗ_КОЛЬОРУ:
        return н
    к = узгодити_колір(колір, рід_назви(н, пара[1]))
    return ("%s %s" % (н, к)) if к and к[:4].lower() not in н.lower() else н


def _з_великої(назва):
    """Перша літера — велика: назва з опису крамниці часом починається з малої."""
    н = str(назва or "").strip()
    return (н[0].upper() + н[1:]) if н else н


def назва_для_показу(o, картки=None):
    """Назва речі для картки + ЗВІДКИ вона й ЧОМУ не та, що у фіді.

    → dict(назва, джерело, причина, оригінал): `джерело` — «фід» / «картка» /
    «опис» / «фраза» / «складено» / «фід (як є)»; `причина` — код `суд_назви`, через який
    назву фіду замінено (None, коли не замінювали); `оригінал` — назва фіду до
    чистки, щоб на картці ніщо не зникало мовчки.

    `картки` — мапа з `читати_назви_карток`; None означає «прочитати самій»."""
    сира = str((o or {}).get("назва") or "")
    пар = (o or {}).get("параметри") or {}
    тип = пар.get("тип")
    слот = пар.get("слот") or (o or {}).get("категорія")
    колір = (o or {}).get("колір_назва") or пар.get("колір")
    _доп = lambda н: _з_великої(доповнити_кольором(н, тип, слот, колір))
    чиста = почистити(сира)
    причина = суд_назви(чиста, сира)
    if not причина:
        return dict(назва=_доп(чиста), джерело="фід", причина=None, оригінал=сира)
    карта = читати_назви_карток() if картки is None else картки
    for url in сторінки_речі((o or {}).get("url")):
        кандидат = почистити(карта.get(url) or "")
        # ОДНЕ СЛОВО З КАРТКИ НЕ БЕРЕМО. Жнива часом ставали на сторінці рубрики,
        # і назва картки там — «Пальта», «Тренчі» (alot, 9 записів): іменник речі
        # в ній є, тож суд її пропускає, а користі від неї менше, ніж від
        # складеної назви, яка принаймні додає колір. Дві слова — найменша назва,
        # яка щось каже понад слот.
        if кандидат and len(кандидат.split()) >= 2 and кандидат != чиста and not суд_назви(кандидат):
            return dict(назва=_доп(кандидат), джерело="картка", причина=причина, оригінал=сира)
    з_оп = почистити(з_опису(чиста or сира, (o or {}).get("опис")) or "")
    if з_оп and not суд_назви(з_оп):
        return dict(назва=_доп(з_оп), джерело="опис", причина=причина, оригінал=сира)
    # ПЕРША ФРАЗА РЕЧЕННЯ. «Яскрава сукня з сяючого люрексу, рукав 3/4,
    # одягається на запах, ремінь вшитий» — назва речі тут Є, просто до неї
    # приклеїли опис. Беремо її, лише якщо вона сама проходить той самий суд:
    # у favoriteshoes «Середня повнота і тонкі ремінці ідеально обіймають ногу»
    # перша фраза теж речення, і джерело мовчить.
    if причина == "речення":
        for шматок in _re.split(r"[,;:]", чиста or ""):
            фраза = почистити(шматок)
            if фраза and фраза != чиста and not суд_назви(фраза):
                return dict(назва=_доп(фраза), джерело="фраза", причина=причина, оригінал=сира)
    # Тип і слот — зі СЛОВНИКА КРАМНИЦІ (`параметри`), як його віддає
    # `читати_yml`; `категорія` — запасний слот, який `feed` уже вивів. Полів
    # запису каталогу тут навмисно нема: назва рахується на картці, а картка
    # приходить із оффера (див. `міст_опис.показ`), і другий шлях, яким ніхто не
    # ходить, лише додав би поле-сироту в аудит контрактів.
    складена = скласти(тип=тип, слот=слот, колір=колір,
                       довжина=пар.get("довжина") or пар.get("довжина_рівень"))
    if складена:
        return dict(назва=_з_великої(складена), джерело="складено", причина=причина, оригінал=сира)
    # НІ ДЖЕРЕЛА, НІ СЛОТА — лишаємо назву фіду й КАЖЕМО про це полем: порожня
    # картка гірша за незграбну назву, а мовчазна підміна гірша за обидві.
    return dict(назва=_доп(чиста or сира), джерело="фід (як є)", причина=причина, оригінал=сира)


def доповнити_опис(опис, назва_фіду, джерело):
    """Назва-речення, яку зняли з картки, — в опис речі: речення не губиться, а йде туди, де доречне."""
    if джерело == "фід" or not назва_фіду:
        return опис
    т = str(опис or "")
    return т if назва_фіду.strip() in т else (назва_фіду.strip() + (". " + т if т else ""))


# ═══════════════ 6. ВІДНОВЛЕНА НАЗВА — ДЛЯ ОБОХ ЧИТАЧІВ (рядок 182) ═══════════
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. Рядок 144 навчив КАРТКУ показувати людську назву, коли
# у фіді стоїть речення з опису, SEO-хвіст чи сам бренд. Слот і тип при цьому
# й далі читались із СИРОЇ назви — і картка з класифікатором казали про ту саму
# річ різне: honchstudio «Обруч Блер чорний» мав тип «джинси» (бо в реченні
# фіду було «з вашою улюбленою джинсовою курткою»), brenda «Штани прямі,
# широкі» лежали у слоті «верх», vilni «Комбінезон лляний» мав тип «сорочка».
# Тип і слот керують вето за типом, пошуком за бажанням, траурним регістром і
# судом дрес-коду, тож хибний тип — це хибний пул, а не лише хибне слово.
#
# ОДНЕ ОБЧИСЛЕННЯ НА ОБОХ ЧИТАЧІВ. Рахувати `назва_для_показу` на кожному
# читанні каталогу не можна: вимір 24.09.2026 на `каталог_повний` — 6.45 с на
# 11 993 оферів, тобто +111 % до `читати_yml` (5.81 с), і це на ноутбуці, а
# продукт крутиться в Pyodide на телефоні. Тому відновлена назва рахується РАЗ,
# офлайн, у `чистка_каталогу.почистити`, і лягає в сам каталог параметром
# `назва_показу` (джерело — в `назва_джерело`). Далі її читають обидва:
# `фід_слот.слот` / `тип_речі` — щоб класифікувати річ тим самим словом, що
# бачить жінка, і `міст_опис.показ` — щоб на картці стояло рівно те, що порахував
# каталог, а не другий, паралельний рахунок.
ПАРАМ_НАЗВИ = "назва_показу"
ПАРАМ_ДЖЕРЕЛА = "назва_джерело"
# Імена решти двох параметрів каталогу будуються від `ПАРАМ_НАЗВИ`: `назва_джерело`
# в оффері вже зайняте ЖНИВАРКОЮ (json-ld / опис / woo / og:title, і `фід_слот`
# його читає), тож власні поля мусять стояти у власному просторі імен.
ПАРАМ_ДЖЕРЕЛА_ПОКАЗУ = ПАРАМ_НАЗВИ + "_джерело"
ПАРАМ_ПРИЧИНИ = ПАРАМ_НАЗВИ + "_причина"

# ЧОМУ САМЕ ЦІ ТРИ ДЖЕРЕЛА, А НЕ ВСІ П'ЯТЬ. «фід» — та сама назва, лише
# почищена: класифікувати нею нічого не міняє. «складено» — назва, ЗІБРАНА з
# `тип` і `слот` самої речі (`скласти`); віддати її назад класифікаторові
# означало б замкнути коло й видати оголошений крамницею тип за прочитаний із
# назви. Лишаються три, у яких назву речі справді ВІДНОВЛЕНО з її сторінки:
# картка крамниці, опис речі, перша фраза назви-речення.
ВІДНОВЛЕНІ_ДЖЕРЕЛА = frozenset(("картка", "опис", "фраза"))

# Версія відновлення. Стоїть у маркері каталогу; коли логіка вище змінюється,
# число тут росте, і `_брудність` бачить, що назви в каталозі лежалі, — без
# повторного рахунку 6.45 с на кожному читанні (саме заради цього маркер і є).
ВЕРСІЯ_ВІДНОВЛЕННЯ = 1


def відновлена_назва(o, картки=None):
    """(назва, джерело, причина) назви, що ЗАМІНИЛА назву фіду, — або (None, None, None).

    Це те саме, що показує картка (`назва_для_показу`), і кладе його в каталог
    `чистка_каталогу`, раз на каталог. Джерело їде поруч, бо читачі в цієї назви
    РІЗНІ й різняться саме ним (див. `фід_слот.назва_суду` і `назва_для_людини`).

    ПРИЧИНА ЇДЕ ТРЕТІМ ЧЛЕНОМ, а не губиться (огляд куратора 24.09, рядок 182):
    власник звіряє у звіті саме ЗАМІНИ, і «картка» без «у фіді: речення» не каже
    йому, ЧОМУ назву фіду відкинуто. Раз назва рахується офлайн, причина мусить
    лягти в каталог поруч із нею — інакше картка її вже не відновить."""
    р = назва_для_показу(o, картки)
    назва = str(р["назва"] or "").strip()
    if not назва or назва == str((o or {}).get("назва") or ""):
        return (None, None, None)
    return (назва, р["джерело"], р["причина"])

