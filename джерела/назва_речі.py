import html as _html
import re as _re

# ═══════════════ 1. РОЗКОДУВАННЯ Й ЧИСТКА ═══════════════
# ГЛИБИНА ТА САМА, ЩО В `чистка_каталогу.ГЛИБИНА_ЕКРАНУВАННЯ`, і з тієї самої
# причини: жниварка нормалізує текст до нерухомої точки, але каталог приходить і
# не від неї. Вимір 23.09.2026 на `каталог_повний`: 189 назв несуть сутність
# (`в&#8217;язки`, `А &#8211; силуету`) — sunwin 95, maxa 35, feelyou 26, morandi 20.
ГЛИБИНА_СУТНОСТЕЙ = 3
_ТЕҐ = _re.compile(r"<[^>]{1,120}>")

def розкодувати(текст):
    """HTML-сутності й теґи геть, пробіли зведено: «гладкої в&#8217;язки» → «гладкої в’язки»."""
    т = str(текст or "")
    for _ in range(ГЛИБИНА_СУТНОСТЕЙ):
        новий = _html.unescape(т)
        if новий == т:
            break
        т = новий
    return _re.sub(r"\s+", " ", _ТЕҐ.sub(" ", т)).strip()


# ── ЧУЖИЙ БЛОК СТОРІНКИ (ricamare ж-01667: під назвою «Дивіться також Коктейльна
# сукня міді…» стоїть фото топа з джинсами). Жниварка взяла заголовок сусіднього
# блоку; назва належить ІНШОМУ товару, тому все від маркера й далі — не ця річ.
# Вимір: 5 записів, усі ricamare; у чотирьох маркер на початку, в ж-03296 —
# усередині («Відмінно міксується з лосинами та джинсами Дивіться також …»).
ЧУЖИЙ_БЛОК = _re.compile(r"\s*(дивіть?ся також|смотрите также|схожі товари|схожі речі|"
                          r"вам також сподобається|з цим товаром купують|ви переглядали)\b.*$", _re.I)

# ── РЕКЛАМНА ОБГОРТКА: кожен рядок — ВИМІРЯНИЙ шаблон однієї крамниці ──────────
# alot (249): «⬆ Вигідна ціна 👍 на Синій сарафан на бретелях ✅, купити Сукні в
#             Києві з доставкою» — справжня назва стоїть між «на» і «✅».
# musthave (230): «… джемпер MH STUDIO, артикул - 16734, 【MustHave ❤️】ціна».
# vittorossi/alot: «… ✅ Замовити онлайн з доставкою ⭐ за ціною: …».
_ОБГОРТКИ = (
    (_re.compile(r"^\s*[^\wа-яіїєґ]*\s*вигідна ціна\s*[^\wа-яіїєґ]*\s*на\s+(.+?)\s*[✅✔☑].*$", _re.I), 1),
    (_re.compile(r"^\s*(?:придбати|купити|купить|замовляйте|замовити|buy)\s+(.+?)\s+[вву]\s+інтернет[-\s]?магазин.*$", _re.I), 1),
)
# Ціна попереду назви: ricamare «1 665 грн Нарядная блуза из гипюра (…)» —
# жниварка взяла рядок разом із цінником. Ціна на картці стоїть своїм полем.
_ГОЛОВИ = (
    _re.compile(r"^\s*\d[\d\s\u00a0\u202f]{2,9}\s*(?:грн|₴|uah)\.?\s*", _re.I),
)
_ХВОСТИ = (
    _re.compile(r"\s*,?\s*артикул\s*[-–—:]?\s*\d+.*$", _re.I),
    _re.compile(r"\s*[,·|]?\s*[^\wа-яіїєґ]{0,4}\s*musthave\s*[^\wа-яіїєґ]{0,4}\s*ціна\s*$", _re.I),
    _re.compile(r"\s*[✅✔⭐⚡❤🤍👍⬆]+.*$"),
    _re.compile(r"\s*[,·|-]\s*(?:ціна|цена)\s*$", _re.I),
)

def зняти_рекламу(назва):
    """Рекламна обгортка й хвіст геть; справжня назва з-під «Вигідна ціна … на X ✅»."""
    н = ЧУЖИЙ_БЛОК.sub("", назва).strip()
    for шаблон, група in _ОБГОРТКИ:
        м = шаблон.match(н)
        if м:
            н = м.group(група).strip()
    for голова in _ГОЛОВИ:
        нов = голова.sub("", н).strip()
        if нов:
            н = нов
    for хвіст in _ХВОСТИ:
        нов = хвіст.sub("", н).strip(" ,·|-–—")
        if нов:
            н = нов
    return н.strip(" ,·|-–—")


# ── СЛУЖБОВИЙ КОД І РОЗМІР У НАЗВІ (вимір 23.09.2026) ────────────────────────
# ricamare (243): «(11, S, Fuchsia, червоний)» — номер варіанта, розмір, колір
#                 крамниці англійською й українською; це поля картки, не назва.
# vittorossi/giardini/attico (1 186): «Уги VS000086107», «… , 1068295».
# solmar (417): «Сукня з бантом, Burgundy - 4129-79»; fromus: «Футболка 2605-1».
# sezone (252): «Лляна сукня максі 402, червоний, 34» — модель, колір, розмір.
# sunwin: «… демісезонна (2859bg)».
# ЩО НЕ ЗРІЗАЄТЬСЯ: голий номер моделі в середині назви (stolyarchuk «МОДЕЛЬ
# №1007») — його зрізання лишило б «Модель», тобто НІЧОГО; такі назви ловить
# `суд_назви` як «нема назви речі» й замінює цілком.
_КОДИ = (
    # Підпис крамниці після вертикальної риски: bella-bicchi «… 26645 | Bella
    # Bicchi», «… 24964 — купити | Bella Bicchi» (190 назв).
    _re.compile(r"\s*\|\s*[^|]{1,40}$"),
    _re.compile(r"\s*[—–-]\s*(?:купити|купить|buy)\s*$", _re.I),
    _re.compile(r"\s*\(\s*\d{1,3}\s*,\s*.{1,80}\)\s*$"),
    _re.compile(r"\s*\(\s*\d{3,6}[a-zа-яіїєґ]{0,4}\s*\)"),
    # miraton: код приклеєно до назви без пробілу — «…коричнева(0031-1)»,
    # «…чорна(LB-25719-1)», «…кемел(999029)» (85 назв разом).
    # У дужках зрізається ЛИШЕ КОД — той, що має цифру. Бренд у дужках
    # («Сукня-футляр трикотажна, з блискавкою на спині (Balmain)») лишається:
    # у brenda саме він і є половина назви, і зняти його було б втратою.
    _re.compile(r"\s*\(\s*(?=[^)]*\d)[A-Za-z0-9][A-Za-z0-9\s.\-]{2,30}\)\s*$"),
    _re.compile(r"[\s,]+(?:[A-Z]{1,4})?\d{5,}\s*$"),
    # welfare: «Рюкзак жіночий Welfare 32130 WHITE/BLK» — артикул і код кольору
    # крамниці латинськими скороченнями (52 назви).
    _re.compile(r"\s+\d{4,6}(?:-[A-Z])?\s+[A-Z][A-Z/.]{1,12}\s*$"),
    # ХВІСТ ІЗ САМИХ СЛУЖБОВИХ ТОКЕНІВ (welfare, 24 назви): «Човники жіночі
    # Tamaris 1-22480-42 378 TAUPE SUEDE» — артикул, номер кольору й код
    # матеріалу крамниці. Зрізається лише хвіст, ПЕРШИЙ токен якого має цифру:
    # інакше під правило потрапила б модель «Сумка жіноча LADIES BAG PERLA»,
    # де великі латинські слова — і є назва.
    _re.compile(r"\s+[A-Z0-9][A-Z0-9/.\-]*\d[A-Z0-9/.\-]*(?:\s+[A-Z0-9][A-Z0-9/.\-]*)*\s*$"),
    _re.compile(r"\s*[-–—]\s*\d{3,5}(?:-\d{1,4})?(?:/\d{1,4})?\s*$"),
    _re.compile(r"\s+\d{3,5}-\d{1,4}(?:/\d{1,4})?\s*$"),
    _re.compile(r"[\s,]+\d{2,5}\s*,?\s*[а-яіїєґ\-\s]{0,20},\s*\d{2}\s*$", _re.I),
    _re.compile(r"[\s,]+\d{2,4}\s*$"),
    # НОМЕР МОДЕЛІ ПОСЕРЕД НАЗВИ І ВСЕ, ЩО ЗА НИМ (sezone, 254 назви): «Лляна
    # сукня максі 402, червоний», «Сукня 2371, 240», «Сукня міді, 191,коричневий
    # в сині квіти» — за номером крамниця дописує свій код кольору й розмір, і
    # це вже не назва. Окремим числом, а не частиною більшого токена: «Сукня
    # №1028 чорний» (№ впритул) і «Сукня 837.3 рожевий» (крапка) лишаються —
    # там номер є частиною того, як крамниця називає модель.
    _re.compile(r"[\s,]+\d{3,5}(?![\d.\-/])(?=[\s,]|$).*$"),
)

# Літерний ПРЕФІКС артикула, що лишився без свого числа: twice «ДЖИНСИ WIDE LEG
# ШОКОЛАДНІ WL 535» → «…шоколадні WL», welfare «Ремінь жіночий Welfare VI 03
# BROWN» → «…Welfare VI». Зрізається ЛИШЕ тоді, коли за ним справді щось зрізали:
# інакше під правило потрапили б emmeliedelage «Кеди бежеві FBC» і onebyone «Боді
# … з вишивкою TOUCH ME», де ці літери й є частина назви (вимір: 125 назв із
# коротким латинським хвостом, з них 106 — залишки коду, 19 — самі назви).
_ЛІТЕРНИЙ_ПРЕФІКС = _re.compile(r"\s+[A-Z]{1,3}\s*$")


def зняти_код(назва):
    """Службовий код, номер варіанта й розмір із хвоста назви — доки лишається сама назва.

    Кожне зрізання відкочується, коли після нього не лишилось жодного слова з
    літерами: «Футболка 2605-1» → «Футболка» (добре), «2605-1» → «» (відкат)."""
    н = назва
    for код in _КОДИ:
        нов = код.sub("", н).strip(" ,·|-–—")
        if _re.search(r"[A-Za-zа-яіїєґА-ЯІЇЄҐ]{3,}", нов):
            н = нов
    if н != назва:
        нов = _ЛІТЕРНИЙ_ПРЕФІКС.sub("", н).strip(" ,·|-–—")
        if _re.search(r"[а-яіїєґА-ЯІЇЄҐ]{3,}", нов):
            н = нов
    return н


def звести_регістр(назва):
    """ВЕЛИКІ ЛІТЕРИ → звичайні: «ТРИКОТАЖНА ЧОРНА СУКНЯ МІДІ» → «Трикотажна чорна сукня міді».

    Чіпає лише кирилицю й лише тоді, коли малих кириличних літер у назві НЕМА
    зовсім (gepur, stolyarchuk, частина alot): латинські слова — бренди
    («MH STUDIO», «LeBERDES») — лишаються як були."""
    if _re.search(r"[а-яіїєґ]", назва) or not _re.search(r"[А-ЯІЇЄҐ]{2,}", назва):
        return назва
    слова = [(w if not _re.search(r"[А-ЯІЇЄҐ]", w) else w.lower()) for w in назва.split(" ")]
    т = " ".join(слова)
    м = _re.search(r"[а-яіїєґ]", т)
    return т[:м.start()] + т[м.start()].upper() + т[м.start() + 1:] if м else т


# Службовий шматок часом зрізається разом із власним хвостом речення, і назва
# лишається на прийменнику: bella-bicchi «…з хутряним декором та 26645 | Bella
# Bicchi» → «…з хутряним декором ТА». Висяче службове слово — не назва.
_ВИСЯЧЕ = _re.compile(r"[\s,]+(та|і|й|з|зі|із|на|в|у|для|від|до|по|при|під|над)\s*$", _re.I)


def почистити(назва):
    """Уся чистка назви одним викликом: сутності → чужий блок і реклама → коди → регістр."""
    н = звести_регістр(зняти_код(зняти_рекламу(розкодувати(назва)))).strip(" ,·|-–—")
    поки = _ВИСЯЧЕ.sub("", н)
    return (поки if поки else н).strip(" ,·|-–—")


