def іменник_речі(назва):
    """Позиція слова, у якому стоїть іменник речі («сукн», «черевик», «dress»), або None.

    КЛЮЧ ІЗ ПРОБІЛОМ НА КІНЦІ — ЦЕ ЦІЛЕ СЛОВО (рядок 185, 24.09.2026). Пробіл у
    «лонг », «сет » писався як «тільки окремим словом»: «сет» стоїть усередині
    «корсета», «лонг» — усередині «лонгсліва». Але шукає ця функція ПО СЛОВАХ, і
    підрядок із пробілом не міг збігтися з жодним словом ніколи — два ключі були
    мертві, а з ними й 112 назв із «лонг» та 61 із «сет». Тепер домовленість
    читається: є пробіл — слово мусить дорівнювати ключеві, нема — як доти."""
    слова = _re.split(r"[\s,·|/]+", str(назва or "").lower())
    для_слова = frozenset(к.strip() for к in _ІМЕННИК if к.endswith(" "))
    підрядки = tuple(к for к in _ІМЕННИК if not к.endswith(" "))
    for i, w in enumerate(слова):
        if w in для_слова or any(к in w for к in підрядки) or any(к in w for к in _ІМЕННИК_ЛАТ):
            return i
    return None


# «Придбати Хустки в інтернет магазині Gepur», «Замовляйте Блузки в інтернет-
# магазині жіночого одягу a LOT» — заголовок СТОРІНКИ РУБРИКИ, а не назва речі:
# жодна крамниця так товару не називає. 14 записів, url усіх веде в `/catalog/`.
_РУБРИКА_ФРАЗА = _re.compile(r"\b[вву]\s+інтернет[-\s]?магазин", _re.I)


def _велики_літери(назва):
    """True, коли в назві нема жодної малої кириличної літери (заголовок рубрики gepur)."""
    return bool(_re.search(r"[А-ЯІЇЄҐ]{2,}", назва)) and not _re.search(r"[а-яіїєґ]", назва)


def _розділ(назва):
    """True, коли це заголовок рубрики сайту, а не назва речі.

    ДВА СВІДКИ, І ДРУГИЙ ОБОВ'ЯЗКОВИЙ, КОЛИ ПЕРШИЙ СЛАБКИЙ (вимір 23.09.2026):
      · сама фраза «… в інтернет-магазині …» — рубрика беззастережно (14 записів
        gepur і alot, url кожного веде в `/catalog/`);
      · назва з самих категорійних слів — рубрика ЛИШЕ у ВЕЛИКИХ ЛІТЕРАХ, як її
        і пише gepur («ПАЛЬТО», «СЕРЕЖКИ», «КОКТЕЙЛЬНІ ПЛАТТЯ»). Без цієї умови
        рубрикою ставали б «Комбінезон» maxa і «Джинсові штани» — справжні назви
        речей, які крамниця пише звичайним регістром (46 записів помилково).
    Назва з самих СЛУЖБОВИХ слів («ЖІНОЧИЙ ОДЯГ», «жіночий одяг») — рубрика в
    будь-якому регістрі: іменника речі в ній нема зовсім."""
    if _РУБРИКА_ФРАЗА.search(str(назва or "")):
        return True
    слова = [w.strip("«»\"'()№.") for w in _re.split(r"[\s,·|/]+", str(назва or "").lower()) if w]
    if not слова or len(слова) > 4:
        return False
    if all(w in РОЗДІЛ_СЛОВА for w in слова):
        return True
    for w in слова:
        if w in РОЗДІЛ_СЛОВА or w in РУБРИЧНІ_МНОЖИНА:
            continue
        if any(к in w for к in _ІМЕННИК) and len(w) <= 12 and not _re.search(r"\d", w):
            continue
        return False
    return _велики_літери(str(назва or ""))


def чужа_мова(назва):
    """Причина, чому назва не українська («російська: …» / «англійська»), або None.

    Російську питає `language_gate.російське` — той самий свідок, яким система
    вже судить власний текст для жінки. Рахується, лише коли він зачепив СЛОВО
    зі словника або дав два свідчення: одна літера в лапках («Гольф теплий
    „ЭММА“») чи ім'я моделі («Зендая») роблять назву не російською, а назвою з
    чужим словом усередині, і міняти її цілком через це було б втратою."""
    if _re.search(r"[A-Za-z]", назва) and not _re.search(r"[а-яіїєґА-ЯІЇЄҐ]", назва):
        return "англійська"
    import language_gate as _LG
    знахідки = _LG.російське(назва)
    словникові = [з for з in знахідки if "слово" in (з.get("чому") or "")]
    # ЗАКІНЧЕННЯ -ое/-ые/-ая/-яя в НАЗВІ — свідчення саме по собі: українська
    # назва речі їх не має. Виняток один і теж виміряний: власне ім'я моделі в
    # хвості назви («…з бантом та рюшами Зендая», dolcedonna, 2 записи) — воно з
    # великої літери й стоїть останнім, і міняти через нього цілу українську
    # назву було б втратою.
    хвіст = (назва.split() or [""])[-1].strip("«»\"'")
    власне_імя = хвіст[:1].isupper() and len(назва.split()) > 1
    закінчення = [з for з in знахідки if "закінчення" in (з.get("чому") or "")
                  and not (власне_імя and str(з.get("фрагмент") or "").strip() == хвіст)]
    if словникові or закінчення or len(знахідки) >= 2:
        return "російська: %s" % (словникові or закінчення or знахідки)[0].get("фрагмент")
    return None


