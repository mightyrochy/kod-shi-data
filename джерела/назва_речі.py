"""назва_речі.py — НАЗВА ДЛЯ ПОКАЗУ: людська назва речі мовою картки (рядок 144 дошки).

ЩО ЦЕ МІНЯЄ В РІШЕННІ. Нічого в доборі пулу й нічого у виборі слота: `назва`
запису лишається байт у байт тією, що прийшла з фіду, і всі шари, які на неї
спираються (`feed.слот`, `тип_речі`, `verify.крій_зі_слова`, ключ моделі),
читають її незмінною. Міняється ТРЕТЄ місце з п.4 CLAUDE.md — пояснення жінці:
на картці стоїть окреме поле `назва_показу`, і саме його бачить людина.

ЧОМУ ОКРЕМЕ ПОЛЕ, А НЕ ПРАВКА `назва` (рішення, не смак). Ручний огляд каталогу
23.09.2026 (47 крамниць, 544 речі очима) знайшов дев'ять класів дефекту назви;
шість із них — рекламний хвіст, службовий код, розмір, регістр, HTML-сутність,
чужий блок сторінки — знімаються без втрати змісту, але три інші (бренд замість
назви, категорія замість назви, речення замість назви) вимагають ЗАМІНИ слова.
Заміна `назва` посунула б слот 1 104 речей, у яких іменника речі в назві нема
зовсім, — а слот рядок 139 править окремо й іншим свідком. Тому тут — показ.

ЗВІДКИ БЕРЕТЬСЯ НАЗВА, ЧОТИРИ ДЖЕРЕЛА ПОІМЕННО (порядок значущий):
  1. `фід`      — назва фіду, почищена (сутності, реклама, коди, регістр). Береться,
                  ЯКЩО пройшла `суд_назви`: назва речі, не розділ, не речення, не
                  чужа мова.
  2. `картка`   — назва з картки крамниці (`назви_карток.json.gz`, зібране жнивами
                  поле `картка.назва`). Вона ж і ПЕРЕКЛАД: коли фід дав російську
                  або англійську, береться картка УКРАЇНСЬКОЇ сторінки тієї самої
                  речі (url без `/ru/`, `/en/`) — тобто перекладає крамниця, не ми.
  3. `опис`     — фраза опису перед брендом у дужках: «… Сарафан вільного крою
                  (Max Mara) Склад: …». Так пишуть картку крамниці, де `<name>` —
                  сам бренд (brenda, 126 із 128 латинських назв).
  4. `складено` — чесно складена назва з ДАНИХ КОДУ: тип речі + довжина + колір,
                  узгоджені за родом. Нічого не вигадано: обидва поля вже є в
                  записі й уже судяться рештою системи.
Джерело завжди їде полем `назва_показу_джерело` — мовчазної підміни нема.

ОРИГІНАЛ НЕ ГУБИТЬСЯ. Назва фіду лишається в `назва` й у `назва_крамниці`, а коли
вона була реченням, `доповнити_опис` дописує її в `опис` речі — речення йде туди,
де воно доречне (крок опису читає `опис`), а не на картку замість назви.
"""
import html as _html
import re as _re

# ═══════════════ 1. РОЗКОДУВАННЯ Й ЧИСТКА ═══════════════
# ГЛИБИНА ТА САМА, ЩО В `чистка_каталогу.ГЛИБИНА_ЕКРАНУВАННЯ`, і з тієї самої
# причини: жниварка нормалізує текст до нерухомої точки, але каталог приходить і
# не від неї. Вимір 23.09.2026 на `каталог_повний`: 189 назв несуть сутність
# (`в&#8217;язки`, `А &#8211; силуету`) — sunwin 95, maxa 35, feelyou 26, morandi 20.
ГЛИБИНА_СУТНОСТЕЙ = 3
_ТЕҐ = _re.compile(r"<[^>]{1,120}>")

def розкодувати(текст):
    """HTML-сутності й теґи геть, пробіли зведено: «гладкої в&#8217;язки» → «гладкої в’язки»."""
    т = str(текст or "")
    for _ in range(ГЛИБИНА_СУТНОСТЕЙ):
        новий = _html.unescape(т)
        if новий == т:
            break
        т = новий
    return _re.sub(r"\s+", " ", _ТЕҐ.sub(" ", т)).strip()


# ── ЧУЖИЙ БЛОК СТОРІНКИ (ricamare ж-01667: під назвою «Дивіться також Коктейльна
# сукня міді…» стоїть фото топа з джинсами). Жниварка взяла заголовок сусіднього
# блоку; назва належить ІНШОМУ товару, тому все від маркера й далі — не ця річ.
# Вимір: 5 записів, усі ricamare; у чотирьох маркер на початку, в ж-03296 —
# усередині («Відмінно міксується з лосинами та джинсами Дивіться також …»).
ЧУЖИЙ_БЛОК = _re.compile(r"\s*(дивіть?ся також|смотрите также|схожі товари|схожі речі|"
                          r"вам також сподобається|з цим товаром купують|ви переглядали)\b.*$", _re.I)

# ── РЕКЛАМНА ОБГОРТКА: кожен рядок — ВИМІРЯНИЙ шаблон однієї крамниці ──────────
# alot (249): «⬆ Вигідна ціна 👍 на Синій сарафан на бретелях ✅, купити Сукні в
#             Києві з доставкою» — справжня назва стоїть між «на» і «✅».
# musthave (230): «… джемпер MH STUDIO, артикул - 16734, 【MustHave ❤️】ціна».
# vittorossi/alot: «… ✅ Замовити онлайн з доставкою ⭐ за ціною: …».
_ОБГОРТКИ = (
    (_re.compile(r"^\s*[^\wа-яіїєґ]*\s*вигідна ціна\s*[^\wа-яіїєґ]*\s*на\s+(.+?)\s*[✅✔☑].*$", _re.I), 1),
    (_re.compile(r"^\s*(?:придбати|купити|купить|замовляйте|замовити|buy)\s+(.+?)\s+[вву]\s+інтернет[-\s]?магазин.*$", _re.I), 1),
)
# Ціна попереду назви: ricamare «1 665 грн Нарядная блуза из гипюра (…)» —
# жниварка взяла рядок разом із цінником. Ціна на картці стоїть своїм полем.
_ГОЛОВИ = (
    _re.compile(r"^\s*\d[\d\s\u00a0\u202f]{2,9}\s*(?:грн|₴|uah)\.?\s*", _re.I),
)
_ХВОСТИ = (
    _re.compile(r"\s*,?\s*артикул\s*[-–—:]?\s*\d+.*$", _re.I),
    _re.compile(r"\s*[,·|]?\s*[^\wа-яіїєґ]{0,4}\s*musthave\s*[^\wа-яіїєґ]{0,4}\s*ціна\s*$", _re.I),
    _re.compile(r"\s*[✅✔⭐⚡❤🤍👍⬆]+.*$"),
    _re.compile(r"\s*[,·|-]\s*(?:ціна|цена)\s*$", _re.I),
)

def зняти_рекламу(назва):
    """Рекламна обгортка й хвіст геть; справжня назва з-під «Вигідна ціна … на X ✅»."""
    н = ЧУЖИЙ_БЛОК.sub("", назва).strip()
    for шаблон, група in _ОБГОРТКИ:
        м = шаблон.match(н)
        if м:
            н = м.group(група).strip()
    for голова in _ГОЛОВИ:
        нов = голова.sub("", н).strip()
        if нов:
            н = нов
    for хвіст in _ХВОСТИ:
        нов = хвіст.sub("", н).strip(" ,·|-–—")
        if нов:
            н = нов
    return н.strip(" ,·|-–—")


# ── АРТИКУЛ КРАМНИЦІ — ТОКЕНОМ, А НЕ ХВОСТОМ (Л-12, 27.09.2026) ──────────────
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. Усі правила `_КОДИ` нижче прикріплені до КІНЦЯ назви
# (`$`), бо вони служать ПОКАЗУ: там назву або дочищають до людської, або суд
# бракує її цілком. Але назва речі живе в каталозі й другим життям — СИРИМ
# полем запису: заяву «код не знає», звіт власника й промпт моделі складають
# саме з нього (та сама причина, через яку зняття сутностей переїхало в
# `чистка_каталогу`, #400). Артикул посеред назви туди доїжджав, і на картці
# ручного проходу 27.09 стояло «Лофери V шкіряні зелені 000399639».
#
# ТОМУ ОКРЕМЕ, ВУЖЧЕ ПРАВИЛО: воно прибирає ТОКЕН службового коду там, де він
# стоїть, і не чіпає нічого іншого. Вужче за `_КОДИ` навмисно — це правило
# застосовується до САМОГО КАТАЛОГУ, тож помилка в ньому нічим не відкочується.
# ЧОГО ВОНО НЕ ЧІПАЄ (рішення власника 27.09):
#   · БРЕНД: токен без жодної цифри («LeBERDES», «(Other Brand)», «WIDE-LEG»,
#     «Palazzo-style») — не код. Так само токен, у якому є ЛІТЕРНЕ СЛОВО від
#     4 літер: «Sky-Star», «East-West», «g-loft» (вимір: 35 таких токенів).
#   · РОЗМІР І КОЛІР: «34», «42», «2XL», «(чорний, 42)», «WHITE/BLK», «721,бежевий»
#     лишаються — їх зрізає лише показ (`_КОДИ`), а в каталозі вони поле речі.
#     Тому голе число до 4 цифр НЕ код: «Сукня 402» — це номер моделі або розмір.
#   · СЕЗОН КОЛЕКЦІЇ: «(2026-2027)» у 24 назвах Tamaris — два роки, не артикул.
# ВИМІР на `каталог_повний.xml` (12 426 оферів, 27.09.2026): голий номер від
# 5 цифр — 1 448 назв, код через дефіс («1-22480-42», «4128-16», «HX20326-4-2»)
# — 493, код у дужках («(2495)», «(2221bg)») — 825, латинський префікс із
# числом («D10142020», «DR015», «VS000086107») — 327.
# ДІАПАЗОНУ РОЗМІРІВ «42-44» У НАЗВАХ ЦЬОГО КАТАЛОГУ НЕМА (вимір: усі п'ять
# токенів «дві цифри — дві цифри» — це коди sunwin «16-02», «19-05»), тож
# двочастинний токен від трьох цифр можна брати як код.
_РІК_КОЛЕКЦІЇ = _re.compile(r"^(?:19|20)\d\d$")
# `&` і `#` у погляді назад, `;` у погляді вперед — щоб не з'їсти цифри
# XML-сутності (`&#65533;`): правило працює і на СИРОМУ тексті каталогу, де
# сутність лишається екранованою на один шар (`чистка_каталогу`).
_ТОКЕН_КОДУ = _re.compile(
    r"(?<![\w&#/-])[0-9A-Za-z]+(?:[-/][0-9A-Za-z]+)*(?![\w/-]|;)")
_ДУЖКИ_КОДУ = _re.compile(r"\s*\(\s*([0-9A-Za-z][0-9A-Za-z-]*)\s*\)")
_ЛІТЕРНЕ_СЛОВО = _re.compile(r"[A-Za-zА-Яа-яІЇЄҐіїєґ]{3,}")
_ОДИН_ШМАТОК = _re.compile(r"^[A-Za-z]{0,4}\d{3,}[A-Za-z]{0,4}$")
МІН_ЦИФР_КОДУ = 3
МІН_ЦИФР_ГОЛОГО = 5
МАКС_ПРОХОДІВ_КОДУ = 3


def _це_службовий_код(токен, у_дужках=False):
    """Чи цей токен — артикул крамниці, а не слово, бренд, розмір чи номер моделі.

    `у_дужках` послаблює тільки одне: голе число в дужках — код уже від трьох
    цифр («(2495)», sunwin/sezone), бо дужки самі й є підписом крамниці, тоді як
    те саме число в тексті назви цілком може бути номером моделі."""
    частини = _re.split(r"[-/]", токен)
    if not any(_re.search(r"\d", ч) for ч in частини):
        return False                                     # бренд або слово
    if all(_РІК_КОЛЕКЦІЇ.match(ч) for ч in частини):
        return False                                     # «2026-2027» — сезон
    if any(ч.isalpha() and len(ч) > 3 for ч in частини):
        return False                                     # у токені є СЛОВО
    цифр = sum(c.isdigit() for c in токен)
    if len(частини) > 1:
        return цифр >= МІН_ЦИФР_КОДУ
    if токен.isdigit():
        return len(токен) >= (МІН_ЦИФР_КОДУ if у_дужках else МІН_ЦИФР_ГОЛОГО)
    return bool(_ОДИН_ШМАТОК.match(токен))


_ПОРОЖНІ_ДУЖКИ = _re.compile(r"\s*\(\s*\)")


def _причесати(назва):
    """Пробіли й розділові знаки після вирізаного токена: «Black - » → «Black»."""
    н = _ПОРОЖНІ_ДУЖКИ.sub("", назва)
    н = _re.sub(r"[ \t]+", " ", н)
    н = _re.sub(r"\s+([,;.])", r"\1", н)
    н = _re.sub(r"([,;])(?:\s*[,;])+", r"\1", н)
    н = _re.sub(r"[\s,;]*[-–—]\s*$", "", н)
    return н.strip(" ,;·|-–—")


def зняти_артикул(назва):
    """Токени службового коду з назви — де б вони не стояли. Решта назви як була.

    Відкочується цілком, коли після зрізання в назві не лишилось жодного слова
    від трьох літер: «000399639» сама по собі — не привід лишити річ без назви."""
    с = str(назва or "")
    н = с
    # ДО НЕРУХОМОЇ ТОЧКИ, а не одним проходом: у дужках крамниці часом лежать ДВА
    # коди через пробіл — miraton «…чорні(418 FT0118)». Перший прохід знімає той,
    # що всередині (`FT0118`), і лише тоді вміст дужок стає одним токеном, який
    # бачить `_ДУЖКИ_КОДУ`. Без циклу в назві лишалось би «(418 )», і другий
    # виклик правила давав би інший результат, ніж перший.
    for _ in range(МАКС_ПРОХОДІВ_КОДУ):
        крок = _ДУЖКИ_КОДУ.sub(
            lambda м: "" if _це_службовий_код(м.group(1), у_дужках=True) else м.group(0), н)
        крок = _ТОКЕН_КОДУ.sub(
            lambda м: "" if _це_службовий_код(м.group(0)) else м.group(0), крок)
        if крок == н:
            break
        н = крок
    if н == с:
        return с
    н = _причесати(н)
    return н if _ЛІТЕРНЕ_СЛОВО.search(н) else с


# ── САМОТНЯ ЛІТЕРА МОДЕЛІ (Л-13, рядок 153, 27.09.2026) ─────────────────────
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. Артикул із назви зняв #405, і «Лофери V шкіряні зелені
# 000399639» стало «Лофери V шкіряні зелені». Лишилась ЛІТЕРА: у giardini код
# моделі стоїть окремим токеном МІЖ типом речі й тканиною, і в сирому полі
# `<name>` — тому в заяві «код не знає», у звіті власника й у тексті, по якому
# `пакет_моделі` шукає бажання жінки, — вона є. Вимір на `каталог_повний`
# (11 828 речей, 47 крамниць): 152 з 335 назв giardini (45 %) несуть таку
# літеру — V 90, F 28, Q 16, D 9, U 6, C 3.
#
# ЧОМУ ПРАВИЛО ТАКЕ ВУЖЧЕ, НІЖ «ЗНЯТИ САМОТНЮ ВЕЛИКУ ЛІТЕРУ». Бо самотня велика
# латинська літера в каталозі буває ЧОТИРЬОХ різних родів, і три з них — назва:
#   · РОЗМІР: «ДЖИНСИ MOM СИНІ M 0003» (twice) — M це розмір;
#   · АНГЛІЙСЬКА ФРАЗА: «Кросівки See U Later», «кепка I don`t give a damn»;
#   · МОДЕЛЬ БРЕНДА: «Браслет золотистого кольору Clic H», «сумка W PM Veau
#     Cachemire» (Hermès) — літера і є ім'я моделі, і зняти її означає втрату;
#   · КОД КОЛЬОРУ: «сумка Welfare 9601 R BLACK».
# Тому знімається літера, яка стоїть ПЕРЕД УКРАЇНСЬКИМ СЛОВОМ (як каже дошка:
# «між типом речі й кольором») або в кінці назви ПІСЛЯ українського слова:
#   «Лофери V шкіряні зелені» → «Лофери шкіряні зелені»
#   «Чоботи Козаки жіночі F»  → «Чоботи Козаки жіночі»
# Перед числом — НЕ знімається («СИНІ M 0003»): токен перед числом належить
# блокові коду й розміру, а не людській назві.
# ЧОГО ПРАВИЛО НЕ ДІСТАНЕ, І ЦЕ НАЗВАНО. «Лофери Жіночі Vicino V» (1 назва):
# літера в кінці після ЛАТИНСЬКОГО слова. За формою це те саме, що «Clic H», і
# розрізнити їх без переліку брендів не можна — тож правило не вгадує.
# ВИМІР ПОКРИТТЯ Й ХИБНИХ СПРАЦЮВАНЬ (усі 11 828 назв каталогу, 47 крамниць):
# правило чіпає 151 назву, усі 151 — giardini; в інших 46 крамницях нуль.
# Проба `проби/litera_modeli_153.py` друкує ці числа й 40 назв до/після.
_УКР = "А-Яа-яІЇЄҐіїєґ"
_ЛІТЕРА_МОДЕЛІ = _re.compile(
    r"(?:(?<=\s)|^)[A-Z](?:(?=\s+[%s])|(?=\s*$))" % _УКР)
_СЛОВО_УКР_ПЕРЕД = _re.compile(r"[%s]\s+$" % _УКР)


def зняти_літеру_моделі(назва):
    """Самотню латинську велику літеру — код моделі — з назви. Решта як була.

    Знімає лише те, що стоїть ПЕРЕД українським словом («Лофери V шкіряні») або
    в кінці назви ПІСЛЯ українського слова («Чоботи Козаки жіночі F»). Решта
    самотніх літер каталогу — розмір («СИНІ M 0003»: за літерою число, не слово),
    англійська фраза («See U Later») або ім'я моделі бренда («Clic H»: літера в
    кінці після ЛАТИНСЬКОГО слова, і відрізнити її від коду за формою не можна).
    Відкочується цілком, коли після зрізання не лишилось слова від трьох літер."""
    с = str(назва or "")
    кінець = len(с.rstrip())
    шматки, поз = [], 0
    for м in _ЛІТЕРА_МОДЕЛІ.finditer(с):
        if м.end() >= кінець and not _СЛОВО_УКР_ПЕРЕД.search(с[:м.start()]):
            continue                      # літера в кінці після латини — ім'я моделі
        шматки.append(с[поз:м.start()])
        поз = м.end()
    if not шматки:
        return с
    н = _причесати("".join(шматки) + с[поз:])
    return н if _ЛІТЕРНЕ_СЛОВО.search(н) else с


# ── ДВО- І ТРИЛІТЕРНИЙ КОД МОДЕЛІ: ОЗНАКА КРАМНИЦІ, А НЕ ФОРМА ТОКЕНА ────────
# (Л-15, рядок 178 дошки; продовження Л-13, яке зняло САМОТНЮ літеру)
#
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. На аркуші giardini (`аудит/проби/огляд_крамниць.py`,
# ручний огляд п.10) жінка бачить «Мокасини PS замшеві сірі», «Черевики QA
# шкіряні чорні», «Лофери SG шкіряні чорні» — 154 назви з кодом моделі всередині.
# Код не називає нічого: він не колір, не матеріал, не форма, і на картці стоїть
# як друкарська помилка.
#
# ЧОМУ НЕ ФОРМА ТОКЕНА (це і є вся суть правки). Рівно той самий токен у трьох
# інших крамницях — СПРАВЖНЄ імʼя моделі: cooshwear «ШТАНИ JIL», «СПІДНИЦЯ МІНІ
# SIA», «СВЕТР AMI» (22 назви), emmeliedelage «Чоботи чорні LEA на шкірі», «Кеди
# бежеві FBC» (13), twice «ДЖИНСИ MOM» (2). Правило за формою («дві-три великі
# латинські літери») зняло б 37 людських назв, і власник побачив би на картці
# «Штани» без імені моделі. Ані довжина, ані голосні, ані частота токена їх не
# розрізняють: giardini має і LB на 37 речах, і SG на восьми, і десяток
# одинаків; cooshwear має GIA на шести.
#
# ОЗНАКА, ЯКА ЇХ РОЗРІЗНЯЄ, І ВОНА НЕ ВГАДАНА. Імʼя моделі належить ОДНІЙ моделі,
# тобто одному РОДУ речі: JIL — це штани, AMI — светр, MOM — джинси, LEA —
# чоботи. Код лінійки чи артикула крамниця ставить на речі РІЗНИХ родів: LB
# стоїть на лоферах, туфлях і черевиках; LAN — на босоніжках і лоферах; CF — на
# балетках і лоферах. Тому крамницю судить один вимір: скільком РОДАМ речей
# (ключ `фід_слот.предмет_назви`, тобто те саме слово, яким система вже називає
# річ) належить той самий токен.
# ВИМІР на `каталог_повний.xml` (11 993 офери, проба
# `джерела/проби/слот_проти_назви.py`):
#   giardini-shoes   154 назви · 21 токен · 8 токенів на ≥2 роди (макс 3) → КОДИ
#   cooshwear         22 назви ·  9 токенів · 0 на ≥2 роди             → назви
#   emmeliedelage     13 назв  ·  8 токенів · 0 на ≥2 роди             → назви
#   twice              2 назви ·  1 токен   · 0 на ≥2 роди             → назви
#   cultboutique       1 назва ·  1 токен   · 0 на ≥2 роди             → назви
# Розрив чистий: 8 проти 0. Поріг — «≥2 токени на ≥2 роди АБО хоч один токен на
# ≥3 роди»: перша половина ловить крамницю, що кодує лінійками, друга — крамницю
# з одним кодом на весь асортимент.
#
# ПОЗИЦІЯ ТОКЕНА — ТА САМА МЕЖА, ЩО В `зняти_літеру_моделі`, і вона вже двічі
# врятувала справжні назви: код стоїть ПІСЛЯ українського слова й ПЕРЕД
# українським словом або в кінці назви. Тому поза виміром лишились musthave
# «Виний однобортний тренч міді MH STUDIO» (за токеном ЛАТИНСЬКЕ слово — це
# бренд «MH STUDIO», а не код) і giardini «Сумка жіноча LADIES BAG PERLA» (перед
# «BAG» стоїть «LADIES», тобто токен усередині латинської назви моделі).
# ПОРІГ ЛИШЕ ПІДНІМАЄ КРАМНИЦЮ ЦІЛКОМ, а не токен: щойно крамницю визнано такою,
# що пише коди, знімаються ВСІ її токени цієї форми, зокрема одинаки (IV, QA,
# LP) — інакше giardini лишалась би з половиною кодів, а число на дошці ніколи не
# дійшло б до нуля. Крамниця, чиї токени — імена моделей, не чіпається зовсім.
_ТОКЕН_МОДЕЛІ = _re.compile(
    r"(?:(?<=\s)|^)[A-Z]{2,3}(?:(?=\s+[%s])|(?=\s*$))" % _УКР)


def _токени_коду(назва):
    """Позиції токенів-кандидатів у назві: 2–3 великі латинські літери на позиції коду."""
    с = str(назва or "")
    return [м for м in _ТОКЕН_МОДЕЛІ.finditer(с)
            if _СЛОВО_УКР_ПЕРЕД.search(с[:м.start()])]


def коди_моделі(назви):
    """Токени-коди моделі ОДНІЄЇ крамниці — або порожня множина, коли це імена моделей.

    `назви` — почищені назви всіх речей крамниці (`почистити`). Рішення про
    крамницю ухвалюється РАЗ, на всьому її асортименті: див. блок вище."""
    роди = {}
    for назва in назви:
        н = str(назва or "")
        р = _предмет_назви(н.lower())
        for м in _токени_коду(н):
            гнізд = роди.setdefault(м.group(0), set())
            if р is not None:
                гнізд.add(р[1])
    багатородні = sum(1 for с in роди.values() if len(с) >= 2)
    if багатородні >= 2 or any(len(с) >= 3 for с in роди.values()):
        return frozenset(роди)
    return frozenset()


def зняти_код_моделі(назва, коди):
    """Дво- й трилітерний код моделі з назви — лише токени з `коди` цієї крамниці.

    Відкочується цілком, коли після зрізання не лишилось слова від трьох літер, —
    та сама межа, що в `зняти_літеру_моделі`."""
    с = str(назва or "")
    if not коди:
        return с
    шматки, поз = [], 0
    for м in _токени_коду(с):
        if м.group(0) not in коди:
            continue
        шматки.append(с[поз:м.start()])
        поз = м.end()
    if not шматки:
        return с
    н = _причесати("".join(шматки) + с[поз:])
    return н if _ЛІТЕРНЕ_СЛОВО.search(н) else с


# ── СЛУЖБОВИЙ КОД І РОЗМІР У НАЗВІ (вимір 23.09.2026) ────────────────────────
# ricamare (243): «(11, S, Fuchsia, червоний)» — номер варіанта, розмір, колір
#                 крамниці англійською й українською; це поля картки, не назва.
# vittorossi/giardini/attico (1 186): «Уги VS000086107», «… , 1068295».
# solmar (417): «Сукня з бантом, Burgundy - 4129-79»; fromus: «Футболка 2605-1».
# sezone (252): «Лляна сукня максі 402, червоний, 34» — модель, колір, розмір.
# sunwin: «… демісезонна (2859bg)».
# ЩО НЕ ЗРІЗАЄТЬСЯ: голий номер моделі в середині назви (stolyarchuk «МОДЕЛЬ
# №1007») — його зрізання лишило б «Модель», тобто НІЧОГО; такі назви ловить
# `суд_назви` як «нема назви речі» й замінює цілком.
_КОДИ = (
    # Підпис крамниці після вертикальної риски: bella-bicchi «… 26645 | Bella
    # Bicchi», «… 24964 — купити | Bella Bicchi» (190 назв).
    _re.compile(r"\s*\|\s*[^|]{1,40}$"),
    _re.compile(r"\s*[—–-]\s*(?:купити|купить|buy)\s*$", _re.I),
    _re.compile(r"\s*\(\s*\d{1,3}\s*,\s*.{1,80}\)\s*$"),
    _re.compile(r"\s*\(\s*\d{3,6}[a-zа-яіїєґ]{0,4}\s*\)"),
    # miraton: код приклеєно до назви без пробілу — «…коричнева(0031-1)»,
    # «…чорна(LB-25719-1)», «…кемел(999029)» (85 назв разом).
    # У дужках зрізається ЛИШЕ КОД — той, що має цифру. Бренд у дужках
    # («Сукня-футляр трикотажна, з блискавкою на спині (Balmain)») лишається:
    # у brenda саме він і є половина назви, і зняти його було б втратою.
    _re.compile(r"\s*\(\s*(?=[^)]*\d)[A-Za-z0-9][A-Za-z0-9\s.\-]{2,30}\)\s*$"),
    _re.compile(r"[\s,]+(?:[A-Z]{1,4})?\d{5,}\s*$"),
    # welfare: «Рюкзак жіночий Welfare 32130 WHITE/BLK» — артикул і код кольору
    # крамниці латинськими скороченнями (52 назви).
    _re.compile(r"\s+\d{4,6}(?:-[A-Z])?\s+[A-Z][A-Z/.]{1,12}\s*$"),
    # ХВІСТ ІЗ САМИХ СЛУЖБОВИХ ТОКЕНІВ (welfare, 24 назви): «Човники жіночі
    # Tamaris 1-22480-42 378 TAUPE SUEDE» — артикул, номер кольору й код
    # матеріалу крамниці. Зрізається лише хвіст, ПЕРШИЙ токен якого має цифру:
    # інакше під правило потрапила б модель «Сумка жіноча LADIES BAG PERLA»,
    # де великі латинські слова — і є назва.
    _re.compile(r"\s+[A-Z0-9][A-Z0-9/.\-]*\d[A-Z0-9/.\-]*(?:\s+[A-Z0-9][A-Z0-9/.\-]*)*\s*$"),
    _re.compile(r"\s*[-–—]\s*\d{3,5}(?:-\d{1,4})?(?:/\d{1,4})?\s*$"),
    _re.compile(r"\s+\d{3,5}-\d{1,4}(?:/\d{1,4})?\s*$"),
    _re.compile(r"[\s,]+\d{2,5}\s*,?\s*[а-яіїєґ\-\s]{0,20},\s*\d{2}\s*$", _re.I),
    _re.compile(r"[\s,]+\d{2,4}\s*$"),
    # НОМЕР МОДЕЛІ ПОСЕРЕД НАЗВИ І ВСЕ, ЩО ЗА НИМ (sezone, 254 назви): «Лляна
    # сукня максі 402, червоний», «Сукня 2371, 240», «Сукня міді, 191,коричневий
    # в сині квіти» — за номером крамниця дописує свій код кольору й розмір, і
    # це вже не назва. Окремим числом, а не частиною більшого токена: «Сукня
    # №1028 чорний» (№ впритул) і «Сукня 837.3 рожевий» (крапка) лишаються —
    # там номер є частиною того, як крамниця називає модель.
    _re.compile(r"[\s,]+\d{3,5}(?![\d.\-/])(?=[\s,]|$).*$"),
)

# Літерний ПРЕФІКС артикула, що лишився без свого числа: twice «ДЖИНСИ WIDE LEG
# ШОКОЛАДНІ WL 535» → «…шоколадні WL», welfare «Ремінь жіночий Welfare VI 03
# BROWN» → «…Welfare VI». Зрізається ЛИШЕ тоді, коли за ним справді щось зрізали:
# інакше під правило потрапили б emmeliedelage «Кеди бежеві FBC» і onebyone «Боді
# … з вишивкою TOUCH ME», де ці літери й є частина назви (вимір: 125 назв із
# коротким латинським хвостом, з них 106 — залишки коду, 19 — самі назви).
_ЛІТЕРНИЙ_ПРЕФІКС = _re.compile(r"\s+[A-Z]{1,3}\s*$")


def зняти_код(назва):
    """Службовий код, номер варіанта й розмір із хвоста назви — доки лишається сама назва.

    Кожне зрізання відкочується, коли після нього не лишилось жодного слова з
    літерами: «Футболка 2605-1» → «Футболка» (добре), «2605-1» → «» (відкат)."""
    н = назва
    for код in _КОДИ:
        нов = код.sub("", н).strip(" ,·|-–—")
        if _re.search(r"[A-Za-zа-яіїєґА-ЯІЇЄҐ]{3,}", нов):
            н = нов
    if н != назва:
        нов = _ЛІТЕРНИЙ_ПРЕФІКС.sub("", н).strip(" ,·|-–—")
        if _re.search(r"[а-яіїєґА-ЯІЇЄҐ]{3,}", нов):
            н = нов
    return н


def звести_регістр(назва):
    """ВЕЛИКІ ЛІТЕРИ → звичайні: «ТРИКОТАЖНА ЧОРНА СУКНЯ МІДІ» → «Трикотажна чорна сукня міді».

    Чіпає лише кирилицю й лише тоді, коли малих кириличних літер у назві НЕМА
    зовсім (gepur, stolyarchuk, частина alot): латинські слова — бренди
    («MH STUDIO», «LeBERDES») — лишаються як були."""
    if _re.search(r"[а-яіїєґ]", назва) or not _re.search(r"[А-ЯІЇЄҐ]{2,}", назва):
        return назва
    слова = [(w if not _re.search(r"[А-ЯІЇЄҐ]", w) else w.lower()) for w in назва.split(" ")]
    т = " ".join(слова)
    м = _re.search(r"[а-яіїєґ]", т)
    return т[:м.start()] + т[м.start()].upper() + т[м.start() + 1:] if м else т


# Службовий шматок часом зрізається разом із власним хвостом речення, і назва
# лишається на прийменнику: bella-bicchi «…з хутряним декором та 26645 | Bella
# Bicchi» → «…з хутряним декором ТА». Висяче службове слово — не назва.
_ВИСЯЧЕ = _re.compile(r"[\s,]+(та|і|й|з|зі|із|на|в|у|для|від|до|по|при|під|над)\s*$", _re.I)


МІН_ПОВТОРУ = 12


def зняти_самоповтор(назва):
    """Хвіст, що ДОСЛІВНО повторює попередній шматок тієї самої назви, — геть.

    ЩО ЦЕ МІНЯЄ В РІШЕННІ (рядок 185, 24.09.2026). sezone ж-04955 пише у фіді
    «Вітрівка з куліскою та коміром стійкою(2452) з куліскою та коміром стійкою,
    402 білий, 34»: артикул і розмір зрізає чистка, а подвоєна фраза лишалась, і
    на картку їхало «Вітрівка з куліскою та коміром стійкою з куліскою та
    коміром стійкою». Доти цього не було видно, бо назву цілком бракував суд.
    МЕЖА 12 СИМВОЛІВ І ДОСЛІВНІСТЬ — щоб не чіпати законних повторів слова
    («Сукня-сорочка сорочкового крою»): 1 запис на каталог_повний, і це він."""
    с = str(назва or "")
    for k in range(len(с) // 2, МІН_ПОВТОРУ - 1, -1):
        хвіст = с[-k:].strip()
        if len(хвіст) >= МІН_ПОВТОРУ and хвіст.lower() in с[:-k].lower():
            return с[:-k].strip(" ,·|-–—")
    return с


def почистити(назва, коди=()):
    """Уся чистка назви одним викликом: сутності → чужий блок і реклама → коди →
    регістр → самотня літера моделі → код моделі крамниці.

    `коди` — токени-коди ЦІЄЇ крамниці (`коди_моделі`, рядок 178); порожньо
    означає «крамниця кодів не пише», і тоді цей крок не робить нічого. Набір
    рахується на всьому асортименті крамниці, тож прийти він може лише зверху —
    від того, хто бачить каталог цілком (`чистка_каталогу.почистити`).
    КОД МОДЕЛІ — ПІСЛЯ САМОТНЬОЇ ЛІТЕРИ, з тієї самої причини, що літера — після
    артикула: доки артикул на місці, за токеном стоїть ЧИСЛО, а не українське
    слово, і правило його не бачить.

    ЛІТЕРА ЙДЕ ОСТАННЬОЮ, І ЦЕ НЕ ПОРЯДОК ЗАРАДИ ПОРЯДКУ (Л-13, рядок 153).
    `зняти_літеру_моделі` знімає літеру лише перед УКРАЇНСЬКИМ словом або в кінці
    назви — а поки `_КОДИ` не зняли артикул, у «Чоботи Козаки жіночі F 000391595»
    за літерою стоїть ЧИСЛО, і правило її не бачить. Після кодів вона остання, і
    правило спрацьовує. Той самий порядок стоїть у `чистка_каталогу`.
    ЧОМУ ТУТ, А НЕ ЛИШЕ В КАТАЛОЗІ: `назва_для_показу` кличе саме `почистити`, і
    без цього рядка `param назва_показу` — те, що бачить ЖІНКА НА КАРТЦІ —
    лишалось би «Лофери V шкіряні зелені» на 153 речах giardini, хоч сире `<name>`
    каталогу вже почищене. Спіймано ручним оглядом (п.10): у каталозі назва чиста,
    а в параметрі — ні."""
    н = звести_регістр(зняти_код(зняти_рекламу(розкодувати(назва)))).strip(" ,·|-–—")
    поки = _ВИСЯЧЕ.sub("", н)
    return зняти_код_моделі(
        зняти_літеру_моделі(зняти_самоповтор((поки if поки else н).strip(" ,·|-–—"))), коди)


