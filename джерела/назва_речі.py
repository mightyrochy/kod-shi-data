def відновлена_назва(o, картки=None, коди=()):
    """(назва, джерело, причина) назви, що ЗАМІНИЛА назву фіду, — або (None, None, None).

    Це те саме, що показує картка (`назва_для_показу`), і кладе його в каталог
    `чистка_каталогу`, раз на каталог. Джерело їде поруч, бо читачі в цієї назви
    РІЗНІ й різняться саме ним (див. `фід_слот.назва_суду` і `назва_для_людини`).

    ПРИЧИНА ЇДЕ ТРЕТІМ ЧЛЕНОМ, а не губиться (огляд куратора 24.09, рядок 182):
    власник звіряє у звіті саме ЗАМІНИ, і «картка» без «у фіді: речення» не каже
    йому, ЧОМУ назву фіду відкинуто. Раз назва рахується офлайн, причина мусить
    лягти в каталог поруч із нею — інакше картка її вже не відновить."""
    р = назва_для_показу(o, картки, коди)
    назва = str(р["назва"] or "").strip()
    if not назва or назва == str((o or {}).get("назва") or ""):
        return (None, None, None)
    return (назва, р["джерело"], р["причина"])

