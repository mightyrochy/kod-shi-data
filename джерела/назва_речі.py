# «Жіноче чорно однотонне класичне вовняне ПАЛЬТО з…» (bella-bicchi) — звичайний
# для крамниць ланцюг означень, і стеля 3 зрізала 47 таких назв помилково.
СТЕЛЯ_СЛІВ_ДО_ІМЕННИКА = 6

def суд_назви(назва, сира=None):
    """Чому ця назва не годиться людині на картку — або None, коли годиться.

    Коди: «порожньо», «розділ», «нема назви речі», «відгук покупчині»,
    «речення», «чужа мова».
    Кожен — окреме поле у звіті, а не одне мовчазне «погана».

    `сира` — назва ДО чистки; рубрику видно саме в ній. Після чистки «Уги
    VS000086107» стає «Уги», тобто однією категорійною словоформою, і невідрізнне
    від рубрики «СУКНІ»; до чистки вони різні, і код не мусить вгадувати."""
    н = str(назва or "").strip()
    if len(н) < 3:
        return "порожньо"
    if _розділ(сира if сира is not None else н):
        return "розділ"
    поз = іменник_речі(н)
    if поз is None:
        return "нема назви речі"
    if _ВІДГУК.search(н):
        return "відгук покупчині"
    if _НАКАЗ.search(н) or _ЗАЙМЕННИК.match(н):
        return "речення"
    # ЗАГОЛОВОК ІЗ ДВОКРАПКОЮ: feelyou «Сила в деталях: чорний атласний костюм…»,
    # stolyarchuk «Базові кольори пасують під все: від куртки до пуховика». Річ
    # названо ПІСЛЯ двокрапки, а перед нею стоїть гасло — і саме воно доїжджало
    # на картку першим рядком. Коли ж перед двокрапкою річ Є («Костюм з паском:
    # туніка…»), це звичайна назва крамниці й чіпати її нема за що.
