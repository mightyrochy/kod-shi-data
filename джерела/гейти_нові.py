# -*- coding: utf-8 -*-
"""ГЕЙТ ПОЛЕГШЕНОГО РЕЖИМУ: димовий прогін системи і проби протоколу. Більше нічого.

ЩО ТУТ БУЛО Й ЧОМУ ЙОГО НЕМА. Цей файл виріс із 471 рядка до 5 355 і йшов понад
пʼять хвилин: сто предметних перевірок, по одній на наряд, кожна з власними
фікстурами. Виміряно на рівнях 1–11 (§0 `НАРЯДИ.md`, 12.09.2026): 70 % злитих
рядків пішло в прилади й тести, а поломки ловились не цим файлом, а прогоном і
читанням диффу. Наряд Н-02-03 (крок 4) просить рівно того, що нижче: тут —
димовий прогін і проби протоколу, решта — `прилади/розділи_гейтів.py`, куди сто
перевірок переїхали цілими, без правки жодної з них. Їх ганяє сесія ревізії раз
на етап і CI, а не кожен наряд.

ЩО ЦЕ ГЕЙТУЄ НАСПРАВДІ — і межа названа вголос:
  · `стенд_знімок.py --дим` (≈1 с) — живий шлях піднімається й не кидає винятку
    на жодному з кроків паспорт → палітри → запити → від_моделі → опис → показ;
  · `тест_протоколу.py` (≈1 с) — шість схем обміну «код ↔ ші» на фікстурах,
    зіпсовані фікстури і звірка переліків, які `протокол.py` тримає копіями.
Це НЕ регресія поведінки: жодне правило тут не судиться, жодне число не
звіряється з учорашнім. Питання, на яке файл відповідає, одне — «чи система
взагалі ходить і чи домовленість про формат ціла». Усе, що тонше, — у
`прилади/розділи_гейтів.py` і `тест_живого_шляху.py`.

ЧОМУ ПІДПРОЦЕСАМИ, А НЕ ІМПОРТОМ. Обидва прилади мають власний код виходу, і
саме він тут вердикт (V34, СТАНДАРТ_КОДУ п. 21). Імпорт з'їв би їхній
`sys.exit` і зробив би цей файл ще одним місцем, де вердикт читає лише око.
Окремий процес ще й тримає їхній стан подалі від нашого: `стенд_знімок` пише
знімки, `тест_протоколу` читає фікстури з `проби/протокол`.

Прогін:  python3 гейти_нові.py ; echo $?     → 0 лише коли зелені ОБИДВА.
"""
import os
import subprocess
import sys
import time

_ТУТ = os.path.dirname(os.path.abspath(__file__)) or "."

# Кожен рядок: (назва, аргументи після python3, скільки чекати).
# Стеля часу — не окраса: наряд приймає цей файл за «укладається в хвилину», і
# зависання мусить називатись зависанням, а не тривати доти, доки набридне.
КРОКИ = (("димовий прогін живого шляху", ["стенд_знімок.py", "--дим"], 120),
         ("проби протоколу «код ↔ ші»", ["тест_протоколу.py"], 120))


def крок(назва, аргументи, чекати):
    """(пройдено, секунд, останній рядок виводу) — і сам вивід друкується як є."""
    почато = time.time()
    try:
        п = subprocess.run([sys.executable] + аргументи, cwd=_ТУТ,
                           capture_output=True, text=True, timeout=чекати)
    except subprocess.TimeoutExpired:
        return False, round(time.time() - почато, 1), "не завершився за %d с" % чекати
    вивід = (п.stdout or "") + (п.stderr or "")
    sys.stdout.write(вивід if вивід.endswith("\n") or not вивід else вивід + "\n")
    рядки = [р for р in вивід.split("\n") if р.strip()]
    return п.returncode == 0, round(time.time() - почато, 1), (рядки[-1] if рядки else "(без виводу)")


def main():
    збої, підсумок = [], []
    for назва, аргументи, чекати in КРОКИ:
        print("\n── %s: python3 %s ─────────────" % (назва.upper(), " ".join(аргументи)))
        пройдено, секунд, останній = крок(назва, аргументи, чекати)
        підсумок.append((назва, пройдено, секунд, останній))
        if not пройдено:
            збої.append(назва)

    print("\n" + "=" * 78)
    for назва, пройдено, секунд, останній in підсумок:
        print("  %s %-32s %5.1f с   %s"
              % ("✓" if пройдено else "✗", назва, секунд, останній))
    print("ПРОЙДЕНО %d, ВПАЛО %d" % (len(підсумок) - len(збої), len(збої)))
    if збої:
        print("  ВПАЛО:", ", ".join(збої))
    else:
        print("  (це димовий гейт, не регресія: сто предметних перевірок — "
              "`python3 прилади/розділи_гейтів.py`, їх ганяє РВ і CI)")
    print("=" * 78)
    return 1 if збої else 0


if __name__ == "__main__":
    sys.exit(main())
