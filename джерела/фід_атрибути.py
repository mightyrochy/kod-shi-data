_ПОЛЕ_МЕТАЛУ = ("метал", "~метал", "~матеріал", "~матеріал верху", "склад", "~склад")
# ── ВИДИМИЙ ТОН І ОСНОВА — РІЗНІ ПОЛЯ, І ТОН ПЕРЕВАЖАЄ (28.09.2026, рядок 161) ──
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. Правила металу (K-CRA-07 «мікс без повтору», K-COL-06-M
# «провідний метал біля обличчя») судять ТОН — те, що видно біля обличчя, — а не
