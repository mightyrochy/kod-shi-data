# Коди `склад_непевний` (їх пише жниварка, `склад_із`), після яких рядок складу не годиться за тканину речі: слово
# волокна завдовжки з речення, зліплені вузли сторінки, відсотки не дають 100. «нема_відсотків» сюди НЕ входить: це склад
# словом без цифр («замша», «натуральна шкіра»), крамниця його сказала, просто без часток.
НЕНАДІЙНИЙ_СКЛАД = frozenset(("слово", "зліплено", "сума_не_100"))


def склад_ненадійний(offer):
    """True, коли жниварка позначила склад речі `склад_непевний` з кодом із `НЕНАДІЙНИЙ_СКЛАД`. Читає коди, не слова
    крамниці (п.12); пул моделі тоді пише `тканина: невідомо`, а не волокно з такого рядка (рядок 6802)."""
    пар = offer.get("параметри") or {}
    if not isinstance(пар, dict):
        return False
    коди = {к.strip() for к in str(пар.get("склад_непевний") or "").split(",")}
    return bool(коди & НЕНАДІЙНИЙ_СКЛАД)


