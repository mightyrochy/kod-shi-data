# Порядок кортежу — і є правило: збіг складеного слова з'їдає свій відрізок, і
# просте слово всередині нього вже не рахується (`_метали_в_тексті`).
МЕТАЛ_ФОРМИ = (
    ("біле_золото", re.compile(r"біл\w*\s+золот|white\s*gold", re.I)),
    ("рожеве_золото", re.compile(r"рожев\w*\s+золот|червон\w*\s+золот|rose\s*gold|pink\s*gold", re.I)),
    ("золото", re.compile(r"золот|позолот|золоч|gold", re.I)),
    ("срібло", re.compile(r"срібл|срібн|посрібл|срібляст|silver", re.I)),
    ("платина", re.compile(r"платин|platinum", re.I)),
    ("сталь", re.compile(r"сталь|сталев|steel", re.I)),
    ("латунь", re.compile(r"латун|brass", re.I)),
    ("бронза", re.compile(r"бронз|bronze", re.I)),
    ("мідь", re.compile(r"мідн|мідь|copper", re.I)),
)


def метали_в_тексті(текст):
    """Перелік металів, названих у тексті, БЕЗ повторів і без слова всередині складеного.

    Порядок `_МЕТАЛ_ФОРМИ` значущий: «біле золото» забирає свій відрізок, і «золот»
    усередині нього вже не дає другого металу. Без цього кожна біла золота каблучка
    називала б ДВА метали й ставала б «двотонною» — вигаданий вхід замість виміряного.
    ДОВЖИНА ПЕРЕЛІКУ — теж відповідь: два різні метали в одному полі означають, що
    продавець назвав ДВА (варіанти «Silver, Gold» у jecomestudio), і вибирати за нього
    код не буде."""
    знайдені, зайнято = [], []
    for ім, рег in МЕТАЛ_ФОРМИ:
        for m in рег.finditer(текст or ""):
            if any(a <= m.start() < b for a, b in зайнято):
                continue
            зайнято.append((m.start(), m.end()))
            if ім not in знайдені:
                знайдені.append(ім)
    return знайдені
# ── СЛОВНИК МЕТАЛІВ — ТОЙ САМИЙ, ЩО В СУДІ (17.09.2026) ─────────────────────
# ЩО ЦЕ МІНЯЄ. `суд_образу` знає шість металів (МЕТАЛИ_ТЕПЛІ = золото, бронза,
# латунь, мідь; МЕТАЛИ_ХОЛОДНІ = срібло, біле_золото, платина, сталь), а сюди
# доїжджали рівно два. Каталог при цьому пише в `параметри["метал"]` ще `сталь`
# (15 речей) і `латунь` (2): фід називає метал тим самим словом, яким його називає
# суд, а перекладач між ними знав два слова з шести. Наслідок для K-CRA-07 («мікс
# без повтору») прямий: сталевий браслет при золотих сережках — це ДВА тони, і
# правило мусить їх побачити; доти сталь просто не існувала, і мікс виглядав
# однотонним.
# ── ВИДИМИЙ ТОН І ОСНОВА — РІЗНІ ПОЛЯ, І ТОН ПЕРЕВАЖАЄ (28.09.2026, рядок 161) ──
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. Правила металу (K-CRA-07 «мікс без повтору», K-COL-06-M
# «провідний метал біля обличчя») судять ТОН — те, що видно біля обличчя, — а не
# сплав основи. Каталог ці два твердження пише різними полями: brenda дає
# `колір: золото` і `~матеріал: нержавіюча сталь` на тій самій речі, і код брав
# основу. ОКОМ (аркуш `огляд_металу.py`, клас `основа_покриття`, 28.09): на 12
# кадрах із фото браслет на зап'ястку золотий рівно там, де поле кольору каже
# «золото», і сріблястий там, де воно каже «срібло»; жоден не читається сталевим.
# Тому: поле КОЛЬОРУ прикраси — видимий тон, поля матеріалу й складу — основа, і
# тон переважає. Позолота на сталі — не суперечність, а дві правдиві заяви про
# різне (рішення власника, рядок 161).
# ЧОМУ ЛИШЕ ЮВЕЛІРНІ СЛОТИ. На поясі й сумці «колір: золото» — це колір ШКІРИ чи
# тканини, а не фурнітури (та сама причина, з якої назва звужена до прикрас), тож
# там лишається як доти: лише поле матеріалу. Прикраса ж уся і є метал.
# Сплави, які носять ПІД покриттям: їх колір у картці — колір покриття, не їхній
# власний. Решта словника називає тон собою («біле золото 585 проби», «платина 950»),
# і для неї склад старший за вільне слово кольору.


def метал(offer, слот_=None):
    """Читає перевірений код розбору без словникового запасного шляху."""
    return КД.ключ(offer, "metal")


# ── КРАМНИЦЯ ДАЄ РІЧ У ДВОХ МЕТАЛАХ, А ГАЛЕРЕЯ ОДНА (28.09.2026, рядок 209) ──
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. `метал` вище повертає ОДИН код, і крок 2 уже вміє сказати
# «названо два — вибирати за продавця код не буде». Але крок 1 (сплав із поля металу)
# стоїть ПЕРЕД ним, тож jecomestudio ж-07556, ж-07612, ж-07620, ж-07621 («колір:
# Silver, Gold» + «метал: золото») доїжджають одним «золотом». Очима: три з чотирьох
# кадрів золоті (поле право), а ж-07556 сріблястий — галерея показує ІНШИЙ варіант.
# Знімати правдивий метал із трьох речей заради однієї код не буде; натомість перелік
# їде в запис, і суд ставить на картку ПИТАННЯ (`суд_річ.метал_не_один_варіант`):
# «крамниця дає цю річ у двох металах, кадр показує один» — вибір лишається жінці
# (аудит/ПРОДУКТ.md п.9). Це та сама механіка, що R-FEED-01 на кольорі варіанта.
def метали_варіантів(offer, слот_=None):
    """Читає перевірений код розбору без словникового запасного шляху."""
    коди = КД.перелік(offer, "metal_variants")
    return [КД.ВМ.ключ("metal", к) for к in коди if к in КД.ВМ.ТАБЛИЦЯ["metal"]] if len(коди) > 1 else []


def метали_в_полях(offer, ключі):
    """Перелік металів, названих у цих полях картки. Порожній — поля нема або воно мовчить.

    Звірка зі словником потрібна, бо поле вільне: «метал: сталь+емаль» має віддати
    «сталь», а «метал: ювелірний сплав» — нічого. Підставляти сусіднє слово тут не
    можна з тієї самої причини, з якої `паспорт_з_json` не підставляє реєстр: вигаданий
    вхід невідрізненний від виміряного. Поля читаються ОДНИМ текстом: «срібло 925 проби
    з позолотою» в одному полі — це два метали на одній речі, і перелік це каже."""
    п = offer.get("параметри") or {}
    т = " ".join(str(п.get(к) or "") for к in ключі).strip()
    return метали_в_тексті(т) if т else []
