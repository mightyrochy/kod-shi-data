# ДОВЖИНА ЗІ СЛОВА — ДЛЯ ВСІХ СЛОТІВ, НЕ ЛИШЕ ВЕРХНЬОГО ШАРУ. Рівень — слово
# каталогу → РІВЕНЬ ТІЛА (не сантиметр): у сантиметри його переводить композитор на
# профілі конкретної людини (той самий принцип, що ХАЛЯВА_ЗА_ТИПОМ). «міні» — свій
# рівень (середина стегна), бо «стегно» верхнього шару — це стегновий ОБХВАТ, куди
# міні-спідниця не сягає. Де ламається: «подовжена» і «вкорочена» — відносні слова,
# їх рівень залежить від слота, і поза верхом/верхнім шаром вони мовчать.

# ── ДОВЖИНА ВИРОБУ В САНТИМЕТРАХ ПРОТИ ЇЇ ЗРОСТУ (28.09.2026, Ф-9) ───────────
# РЯДОК 84 ВІДКРИТО ВЛАСНИКОМ 28.09 РІВНО НА ЦЕ, І БІЛЬШ НІ НА ЩО: канал обмірів
# зішкребеної сторінки заводиться ЛИШЕ для довжини виробу проти зросту профілю.
# Розмір, обхвати виробу й решта обмірів лишаються не заведеними, як і доти.
#
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. Рівень довжини («міді») — слово, і `композитор_річ.висота_
# рівня` переводить його в сантиметри ЗОНОЮ ±7 см: `fit.краї` над такою зоною виходить
# «питанням», щойно її смуга накриває найширше місце лише частково, а сила вердикту
# зрізана до `soft` (T3 ≤ вимір). Оголошена довжина виробу знімає обидва обмеження:
# поділ рахується арифметикою `рівень виміру на тілі − довжина виробу`, і та сама
# «міді» 94 см кладе поділ на 158 см і на 175 см у РІЗНІ класи.
#
# ТОЧКА ВИМІРУ — ОКРЕМЕ ПОЛЕ, БО 79 СМ І 79 СМ — ЦЕ РІЗНІ МІСЦЯ. Крамниці міряють від
# трьох різних місць, і кожне зустрічається в каталозі сотнями: «довжина по спині» /
# «довжина виробу» — від плечей, «довжина штанини» / «довжина спідниці» / «по боковому
# шву з поясом» — від талії, «довжина крокового шва» — від паху. Кроковий шов 79 см на
# зрості 165 кладе поділ на 0 см від підлоги, спідниця 79 см — на 23 см. Без точки
# виміру одне з двох чисел було б помилкою в 23 см, тобто цілим класом довжини.
#
# РОЗКИД — НЕ КОСМЕТИКА: розмірна сітка крамниці дає ОДНУ довжину на розмір («S - 61,
# M - 62, L - 62, XL - 66»), а свого розміру жінка коду не називала. Півширина сітки
# і є честю цього виміру; там, де крамниця дає одне число, лишається шва-допуск
# `_ДОВЖИНА_ДОПУСК_СМ`. «Довжина по спині» міряється від СЬОМОГО ХРЕБЦЯ, а `висоти`
# тіла знають рівень «плечі» — різницю ми не вигадуємо константою, а кладемо в розкид
# (`_СПИНА_РОЗКИД_СМ`): невідоме зміщення чесніше як ширша зона, ніж як точне число.
#
# МЕЖІ 20–180 СМ — НЕ ШКАЛА, А ЗАХИСТ ВІД БРУДУ: «Довжина» прикраси (3 см) і габарит
# сумки живуть у тих самих полях, а перевірку «поділ на тілі» робить уже композитор
# (`край_з_довжини` віддає None, коли число кладе поділ поза тілом).
# точка за замовчуванням — за слотом: у верху, сукні й верхньому шарі «довжина виробу»
# міряється від плечей, у низу — від талії. Слоти ті самі, у яких є ПОДІЛ (`довжина_речі`).
ДОВЖИНА_СІТКА = re.compile(r"[-–—]\s*(\d{2,3})(?:[.,]\d)?\s*(?:см|cм|cm)?", re.I)
# «115-120 см» — не сітка розмірів, а ВІЛКА самої крамниці на одну річ: без цього
# рядка сітковий вираз брав із неї лише праве число й губив половину зони
ДОВЖИНА_ВИЛКА = re.compile(
    r"^\s*(\d{2,3})(?:[.,]\d)?\s*[-–—]\s*(\d{2,3})(?:[.,]\d)?\s*(?:см|cм|cm)?\.?\s*$", re.I)
ДОВЖИНА_МЕЖІ_СМ = (20.0, 180.0)
ДОВЖИНА_ДОПУСК_СМ = КД.ДОПУСК_ДОВЖИНИ_СМ
СПИНА_РОЗКИД_СМ = 2.5


def довжини_зі_значення(знач):
    """Числа в см зі значення param: «120», «81 см» або «S - 61, M - 62, L - 62» (розмірна
    сітка крамниці). Поза межами `_ДОВЖИНА_МЕЖІ_СМ` число не береться: у полях з тим самим
    іменем живуть і 3 см ланцюжка, і габарит сумки."""
    т = str(знач or "").strip()
    if not т:
        return []
    в = ДОВЖИНА_ВИЛКА.match(т)
    сп = ([float(в.group(1)), float(в.group(2))] if в
          else [float(x) for x in ДОВЖИНА_СІТКА.findall(т)])
    if not сп:
        о = число_з_поля(т)
        сп = [о] if о is not None else []
    низ, верх = ДОВЖИНА_МЕЖІ_СМ
    return [x for x in сп if низ <= x <= верх]


def довжина_виробу(offer, сл):
    """Читає перевірений код розбору без словникового запасного шляху."""
    см = КД.число(offer, "length_cm")
    точка = {"shoulder": "плечі", "waist": "талія", "inseam": "пах"}.get(КД.код(offer, "length_anchor"))
    return см, точка, ДОВЖИНА_ДОПУСК_СМ if см is not None else None, КД.джерело_рядком(offer, "length_cm")


def клас_довжини_для_слота(клас, сл):
    """Чи можна цей рівень поділу ставити слотові в поле `довжина_рівень`. Та сама
    умова, якою `довжина_речі` відсіює СЛОВА крамниці, і живе вона в одному місці:
    «міні» у верху означає комплект зі спідницею, а відносні «талія»/«стегно» поза
    верхом і верхнім шаром нічого не кажуть. Другий читач — `композитор_річ.у_річ`,
    який заповнює поле ВИМІРЯНИМ класом, коли слова крамниця не дала."""
    if клас is None:
        return False
    if сл == "верх" and клас in ("міні", "максі"):
        return False
    if сл not in ("верх", "верхній_шар") and клас in ("талія", "стегно"):
        return False
    return True


def довжина_речі(offer, сл):
    """Читає перевірений код розбору без словникового запасного шляху."""
    return клас_довжини_для_слота(КД.ключ(offer, "length"), сл), КД.джерело_рядком(offer, "length")


