# ── ДВІ ДОВЖИНИ АКСЕСУАРІВ: ЛИШЕ ЧИСЛО З ПОЛЯ (K-EDG-01, K-JEW-01) ──────────────
# `ремінь_см` — падіння ременя сумки = половина повної довжини з поля `~ручка` (ремінь, накинутий на
# плече, — замкнена петля); коротша за `_РУЧКА_МІН_СМ` ручка краю не дає. `ланцюг_см` — число з поля
# `довжина_см` прикраси. Слова опису («ремінь 120 см») більше не читаються.
_РУЧКА_МІН_СМ = 40.0
_ЧИСЛО_ПОЛЯ = re.compile(r"^\s*(\d{1,3})(?:[,.]\d+)?\s*(?:см|cм|cm)?\s*$", re.I)
_ЛАНЦЮГ_СЛОТИ = ("прикраси", "кольє", "намисто")


def _число_з_поля(знач):
    """Значення param → число в см, або None. Картка пише і «120», і «14 см», і «17 cм»
    (з ЛАТИНСЬКОЮ `c`)."""
    if знач in (None, ""):
        return None
    м = _ЧИСЛО_ПОЛЯ.match(str(знач))
    return float(м.group(1)) if м else None


def _повна_ручка(offer):
    """(довжина ручки/ременя сумки в см, звідки взялась) або (None, None): лише поле `~ручка`."""
    повна = _число_з_поля((offer.get("параметри") or {}).get("~ручка"))
    return (повна, "поле картки «ручка»") if повна is not None else (None, None)


