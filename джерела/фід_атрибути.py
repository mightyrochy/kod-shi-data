# ── СКЛАД МАГАЗИНУ В ПОЛЕ `матеріал` (11.09.2026, наряд Н-V14-029) ───────────
# ЩО ЦЕ МІНЯЄ (before/after, каталог_повний, 10 749 речей зі слотом):
#   before: `матеріал` не писав НІХТО — ні цей файл, ні `pipeline`. Над полем
#           стояли ТРИ читачі: `outer.догляд` (K-OUT-44/45 — сіль проти вовни,
#           шовку, шкіри й замші), `outfit` K-WEA-01 (ВОЛОГІ_ВЕТО — замша в дощ)
#           і `pipeline._поля_групи` (рядок пулу для моделі). Тобто тема солі
#           судила образ за ознакою, якої на живому шляху не існує.
#   after:  оголошений склад є в 642 із 764 речей слота верхній_шар (84 %), і
#           K-OUT-44 на реагентах піднімається з 188 до 293 речей того ж слота.
# ЧОМУ ЛИШЕ `param склад` І ЙОГО ДІАЛЕКТИ, А НЕ `матеріал_родина` (100 % речей):
# коментар цього ж файлу вище вже виміряв, що родина розходиться зі «Складом»
# магазину в 57 % (4 082 із 7 189) і ЗАВЖДИ в бік благороднішого волокна
# («100 % бавовна» → «вовна», «100 % поліестер» → «шовк»). Родина — мітка
# розділу магазину, не матеріал речі, і брати її тут означало б живити сольове
# вето вигадкою збирача.
# ЧОМУ РЯДОК ЯК Є, БЕЗ НОРМАЛІЗАЦІЇ В ОДИН ТЕРМІН: читачі шукають ОСНОВУ
# (`outer._основи` — від початку слова, `ВОЛОГІ_ВЕТО` — підрядком), і «50%
# Вовна, 30% Віскоза» віддає їм «вовн» без жодного словника. Нормалізація в
# один термін мусила б ОБРАТИ одне волокно з трьох — тобто вгадати частку, якої
# в рядку в 2/3 випадків не видно. Вузьке нормалізоване слово вже є окремо:
# `волокно` (V.волокно_зі_слова, найдовший корінь) — і саме тому воно тут не
# замінник: на «60% віскоза, 40% вовна» найдовший корінь віддає «віскоза», і
# вовна — та ознака, задля якої K-OUT-44 писалось, — зникає.
_МАТЕРІАЛ_КЛЮЧІ = ("склад", "~склад", "~матеріал", "~матеріал верху",
                   "~матеріал ззовні", "~склад тканини")


def матеріал_речі(offer):
    """(рядок складу в нижньому регістрі, за_чим) або (None, None).

    Перший ключ, що має значення, виграє: живе ім'я цього каталогу (`склад`,
    266 оферів brief) стоїть попереду діалектних (`~склад` 103, `~матеріал` 94,
    `~матеріал верху` 34). `матеріал_родина` СЮДИ НЕ ЙДЕ — див. блок вище."""
    пар = offer.get("параметри") or {}
    if not isinstance(пар, dict):
        return None, None
    for к in _МАТЕРІАЛ_КЛЮЧІ:
        v = str(пар.get(к) or "").strip().lower()
        if v:
            return v, ["param %s" % к]
    return None, None


# ── ЧАСТКА ЕЛАСТАНУ ЗІ СКЛАДУ (28.09.2026, Ф-4, звіт Research §5) ───────────
# НАВІЩО. Умова застосування мінімумів носіння й вікна ковзання — ПОЛОТНО: «у трикотажі
# припуск є функцією розтяжності й регулярно від'ємний, там правило не діє зовсім»
# (тема-1 §17.1, і це вже сказано в `ламається` кожної знахідки K-BOD-02). Тканина з
# еластаном веде себе так само: річ облягає, бо так скроєно й так тягнеться, — а
# K-BOD-02 читав те саме від'ємне відхилення як провал «облягає широку зону». Поле
# `текстура` ловить лише те, що крамниця назвала словом («трикотаж»), а склад називають
# набагато частіше за конструкцію.
# ЩО САМЕ ВИДОБУВАЄТЬСЯ. Число у відсотках, не прапорець: різниця між 2 % (стабілізація
# полотна) і 18 % (компресійний трикотаж) — це різниця в тому, чи припуск узагалі щось
# означає. Коли волокно НАЗВАНЕ, а частки не видно («вовна, еластан, поліестр»), поле
# лишається None — це «невідомо», а не нуль.
# ЧОМУ З `матеріал_речі`, А НЕ З ОПИСУ. Опису в речі каталогу немає як поля (його
# читають окремі шари), а оголошений склад є: виміряно на `каталог_повний` (11 828
# речей) — еластан названий у 1 962 речах, частка читається в 1 960 із них (99.9 %).
_ЕЛАСТАН_СЛОВО = (r"(?:еластан|спандекс|elastane|spandex|лайкр|lycra|ела\s?стан)")
_ЕЛАСТАН_ЧИСЛО = r"(\d{1,2}(?:[.,]\d)?)"
# ДВІ ФОРМИ, І ОБИДВІ ВИМІРЯНІ НА КАТАЛОЗІ. Крамниці пишуть і «5% еластан», і
# «еластан (elastane) - 3%». Необов'язкове слово між числом і волокном закриває
# «27% перероблений еластан»; кома й цифра в нього не входять, щоб частка сусіднього
# волокна не приклеїлась до еластану.
_ЕЛАСТАН_ФОРМИ = (
 re.compile(_ЕЛАСТАН_ЧИСЛО + r"\s*%?\s*[-–:]?\s*(?:[а-яіїєґa-z]+\s+)?" + _ЕЛАСТАН_СЛОВО, re.I),
 re.compile(_ЕЛАСТАН_СЛОВО + r"\w*\s*(?:\([^)]{0,24}\))?\s*[-–:]?\s*" + _ЕЛАСТАН_ЧИСЛО + r"\s*%", re.I),
)
_ЕЛАСТАН_Є = re.compile(_ЕЛАСТАН_СЛОВО, re.I)


def еластан_речі(offer):
    """(частка еластану у відсотках або None, за_чим).

    None у першому полі має ДВА різні значення, і друге поле їх розрізняє:
    `за_чим` порожній — складу нема зовсім; `за_чим` є, а частки нема — волокно
    названо, відсотка крамниця не пише. Читач (K-BOD-02) мусить бачити різницю:
    «не знаю тканини» і «тканина тягнеться, скільки — невідомо» ведуть до різного."""
    склад, за_чим = матеріал_речі(offer)
    if not склад or not _ЕЛАСТАН_Є.search(склад):
        return None, None
    for ф in _ЕЛАСТАН_ФОРМИ:
        g = ф.search(склад)
        if g:
            return float(g.group(1).replace(",", ".")), (за_чим or []) + ["склад"]
    return None, (за_чим or []) + ["склад: волокно назване, частки нема"]


