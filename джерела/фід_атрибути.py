# ── ДОВЖИНА ВИРОБУ В САНТИМЕТРАХ: ЛИШЕ ЧИСЛО З ПОЛЯ `довжина` (Ф-9, рядок 5192) ──
# Раніше ключ вибирався за словами («довжина крокового шва», «по спині», «від талії»), точка виміру
# читалась зі слів ключа, а опис давав «довжину 60 см» регуляркою. Тепер: лише поле, ім'я якого —
# рівно `довжина` (зі службовими `~•·` на початку), значення — число з одиницею або розмірна сітка;
# точка виміру — за слотом (закритий код). Слова ключа й опису не читаються.
_ДОВЖИНА_ТОЧКА_СЛОТА = {"сукня": "плечі", "комплект": "плечі", "верх": "плечі",
                        "верхній_шар": "плечі", "низ": "талія"}
_ДОВЖИНА_СІТКА = re.compile(r"[-–—]\s*(\d{2,3})(?:[.,]\d)?\s*(?:см|cм|cm)?", re.I)
_ДОВЖИНА_ВИЛКА = re.compile(
    r"^\s*(\d{2,3})(?:[.,]\d)?\s*[-–—]\s*(\d{2,3})(?:[.,]\d)?\s*(?:см|cм|cm)?\.?\s*$", re.I)
_ДОВЖИНА_МЕЖІ_СМ = (20.0, 180.0)
_ДОВЖИНА_ДОПУСК_СМ = 2.0


def _довжини_зі_значення(знач):
    """Числа в см зі значення param: «120», «81 см» або «S - 61, M - 62, L - 62» (розмірна
    сітка крамниці). Поза межами `_ДОВЖИНА_МЕЖІ_СМ` число не береться."""
    т = str(знач or "").strip()
    if not т:
        return []
    в = _ДОВЖИНА_ВИЛКА.match(т)
    сп = ([float(в.group(1)), float(в.group(2))] if в
          else [float(x) for x in _ДОВЖИНА_СІТКА.findall(т)])
    if not сп:
        о = _число_з_поля(т)
        сп = [о] if о is not None else []
    низ, верх = _ДОВЖИНА_МЕЖІ_СМ
    return [x for x in сп if низ <= x <= верх]


def довжина_виробу(offer, сл):
    """(довжина виробу в см, точка виміру на тілі, розкид см, за_чим) або чотири None.

    Лише поле з іменем `довжина`; точка — код слота (`_ДОВЖИНА_ТОЧКА_СЛОТА`), розкид — півширина
    розмірної сітки, не менш за допуск. Поля з названою точкою («крокового шва», «по спині») та
    слова опису тут не читаються: точка виміру з них — слова, а без точки число лишається
    «невідомим» (помилка точки — це ціла класа довжини, див. Ф-9)."""
    if сл not in _ДОВЖИНА_ТОЧКА_СЛОТА:
        return None, None, None, None
    пар = offer.get("параметри") or {}
    for ім in sorted(пар):
        if str(ім).lstrip("~•· ").strip().lower() != "довжина":
            continue
        чис = _довжини_зі_значення(пар[ім])
        if чис:
            см = round((min(чис) + max(чис)) / 2, 1)
            розкид = round(max(_ДОВЖИНА_ДОПУСК_СМ, (max(чис) - min(чис)) / 2), 1)
            return см, _ДОВЖИНА_ТОЧКА_СЛОТА[сл], розкид, "param картки «довжина» = %s" % пар[ім]
    return None, None, None, None


def клас_довжини_для_слота(клас, сл):
    """Чи можна цей рівень поділу ставити слотові в поле `довжина_рівень`: «міні» у верху означає
    комплект зі спідницею, а відносні «талія»/«стегно» поза верхом і верхнім шаром нічого не кажуть.
    Закриті коди рівнів і слотів. Читач — `композитор_річ._у_річ`."""
    if клас is None:
        return False
    if сл == "верх" and клас in ("міні", "максі"):
        return False
    if сл not in ("верх", "верхній_шар") and клас in ("талія", "стегно"):
        return False
    return True


