def обʼєкт(поля, треба=()):
    """Вузол-обʼєкт: оголошені поля і ті з них, без яких обʼєкт не обʼєкт."""
    return dict(тип="обʼєкт", поля=dict(поля), треба=tuple(треба))


def карта(по_ключу):
    """Вузол-карта: ключі вільні (слот, ід), значення — усі однієї форми."""
    return dict(тип="карта", по_ключу=по_ключу)


def список(елемент, мін=None, макс=None):
    """Вузол-список із межами довжини. `мін=1` = «порожній список тут — помилка»."""
    return dict(тип="список", елемент=елемент, мін=мін, макс=макс)


def слово(*значення):
    """Рядок із переліку. Enum — єдина перевірка, яка ловить «майже те саме слово»."""
