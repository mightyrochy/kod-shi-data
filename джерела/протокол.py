# ── ВАЛІДАТОР ────────────────────────────────────────────────────────────────
_ІМЕНА_ТИПІВ = {str: "рядок", bool: "логічне", int: "ціле", float: "число",
                list: "список", tuple: "список", dict: "обʼєкт", type(None): "порожнє"}


def _як_звати(v):
    """Тип значення словом для повідомлення про розходження — з `_ІМЕНА_ТИПІВ`,
    інакше питоняче імʼя типу."""
    return _ІМЕНА_ТИПІВ.get(type(v), type(v).__name__)


def _тип_en(ім):
    """Імʼя типу схеми → код типу в `що` розходження (`_ТИПИ_EN`); порожнє — `null`."""
    return "null" if ім == "порожнє" else _ТИПИ_EN.get(ім, ім)


def _пом(шлях, що):
    """Одне розходження схеми: де воно й що саме. Порожній шлях — «корінь».
    `що` валідатора — КОД із числами (`wrong_type(got=string,need=list)`), не фраза (рядок 3442,
    аудит/ПРОДУКТ.md п.12): його читає звіт, а моделі в повтор — англійським шаблоном `_ПОМИЛКИ_EN`."""
    return dict(де=шлях or "корінь", що=що)


def _нижче(шлях, ключ):
    """Шлях на рівень нижче: «людина» + «тіло» → «людина.тіло»."""
    return ключ if not шлях else "%s.%s" % (шлях, ключ)


def перевірити(схема, об, шлях=""):
    """→ список помилок `{де, що}`. Порожній список = обʼєкт відповідає схемі.

    Помилки збираються ВСІ, а не перша: повторний виклик до моделі має сенс лише
    тоді, коли називає все, що не так (§1(б) — один повторний виклик, далі чесна
    відмова). Зупинка на першій помилці дала б три виклики там, де досить одного.

    Зламана СХЕМА — це ValueError, а не запис у списку помилок. Дефект коду і
    дефект даних не мають права їхати одним каналом: інакше `завдання.відповідь`
    із друкарською помилкою в самій схемі виглядав би як «модель не тримає формат».
    """
    вузол = схема if isinstance(схема, dict) else None
    if вузол is None or вузол.get("тип") not in ТИПИ:
        raise ValueError("схема зламана: невідомий тип «%s» у «%s»"
                         % ((вузол or {}).get("тип"), шлях or "корінь"))
    т = вузол["тип"]
    if об is None:
        return [] if вузол.get("нуль") else [_пом(шлях, "null_not_allowed")]
    if т == "будь_що":
        return []
    # ── СКАЛЯРИ ──────────────────────────────────────────────────────────────
    if т in ("рядок", "число", "ціле", "логічне"):
        ок = {"рядок": lambda v: isinstance(v, str),
              # bool — підклас int у Python: без явного відсіву `True` пройшов би
              # як ціле, і «ітерація: true» стало б валідним вердиктом
              "ціле": lambda v: isinstance(v, int) and not isinstance(v, bool),
              # inf/NaN — не число вимірювання (рядок 1991): JSON їх не має, а `x != x` ловить NaN
              "число": lambda v: isinstance(v, (int, float)) and not isinstance(v, bool)
                                 and v == v and v not in (float("inf"), float("-inf")),
              "логічне": lambda v: isinstance(v, bool)}[т](об)
        if not ок:
            return [_пом(шлях, "wrong_type(got=%s,need=%s)" % (_тип_en(_як_звати(об)), _тип_en(т)))]
        # enum — ПІСЛЯ типу: «не той тип» не має перетворюватись у «не те значення»
        якщо_перелік = вузол.get("значення")
        if якщо_перелік and об not in якщо_перелік:
            return [_пом(шлях, "not_one_of(«%s»: %s)"
                         % (об, ", ".join(str(z) for z in якщо_перелік)))]
        return []
    # ── СПИСОК ───────────────────────────────────────────────────────────────
    if т == "список":
        # tuple приймається разом зі list: код будує пакет кортежами
        # (`pipeline.пакет_для_моделі`: `слоти_альт=tuple(...)`), а `json.dumps`
        # робить із них масив. Валідувати можна і до, і після dumps.
        if not isinstance(об, (list, tuple)):
            return [_пом(шлях, "wrong_type(got=%s,need=list)" % _тип_en(_як_звати(об)))]
        пом = []
        if вузол.get("мін") is not None and len(об) < вузол["мін"]:
            пом.append(_пом(шлях, "list_too_short(n=%d,min=%d)" % (len(об), вузол["мін"])))
        if вузол.get("макс") is not None and len(об) > вузол["макс"]:
            пом.append(_пом(шлях, "list_too_long(n=%d,max=%d)" % (len(об), вузол["макс"])))
        for i, x in enumerate(об):
            пом += перевірити(вузол["елемент"], x, "%s[%d]" % (шлях, i))
        return пом
    # ── КАРТА ────────────────────────────────────────────────────────────────
    if т == "карта":
        if not isinstance(об, dict):
            return [_пом(шлях, "wrong_type(got=%s,need=map)" % _тип_en(_як_звати(об)))]
        пом = []
        for k in sorted(об, key=str):          # sorted → порядок помилок стабільний
            if not isinstance(k, str):
                пом.append(_пом(шлях, "key_not_string(«%s»)" % k))
                continue
            пом += перевірити(вузол["по_ключу"], об[k], _нижче(шлях, k))
        return пом
    # ── ОБʼЄКТ ───────────────────────────────────────────────────────────────
    if not isinstance(об, dict):
        return [_пом(шлях, "wrong_type(got=%s,need=object)" % _тип_en(_як_звати(об)))]
    пом = []
    for k in вузол["треба"]:
        if k not in об:
            пом.append(_пом(_нижче(шлях, k), "required_missing"))
    for k, в in вузол["поля"].items():
        if k in об:
            пом += перевірити(в, об[k], _нижче(шлях, k))
    return пом


# ── ОДНА ТОЧКА РОЗБОРУ ───────────────────────────────────────────────────────
_У_ДУЖКАХ = _re.compile(r"```(?:json)?\s*(\{.*?\})\s*```", _re.S)


def _кандидати(т):
    """Три місця, де у відповіді моделі буває JSON, за спаданням явності.

    ЦІЛИЙ ТЕКСТ СТОЇТЬ ПЕРЕД ВИРІЗАННЯМ ПО ДУЖКАХ НАВМИСНО. Зріз «від першої `{`
    до останньої `}`» завжди починається з `{`, тобто завжди дає обʼєкт або
    провал розбору — і через це відповідь-МАСИВ (модель віддала сам список
    образів замість обʼєкта з полем `образи`) перетворювалась у ПЕРШИЙ образ, а
    решта девʼять зникали без жодного слова. Це рівно та тиха втрата, проти якої
    цей модуль і написаний. Тепер масив розбирається цілим і дістає імʼя
    (`json_not_object`), а зріз лишається останньою спробою для відповіді,
    обгорнутої прозою.
    """
    м = _У_ДУЖКАХ.search(т)
    if м:
        yield м.group(1)
    yield т
    a, b = т.find("{"), т.rfind("}")
    if a >= 0 and b > a and т[a:b + 1] != т:
        yield т[a:b + 1]


# Причини невдалого розбору — КОДИ, не фрази (п.12, кошик В): внутрішня мова, що не ламається від
# локалізації. Споживачі — повторний виклик (`помилка_формату`, англійським дротом код розкладають
# `_ПОМИЛКИ_EN`), `прийняти_розмову.причина` і звіт власника; слова для людини дає мовна модель.
#   empty_answer · no_json_object[(prose)] · invalid_json(line=L,col=C) · json_not_object(<тип>)
КОД_ТИПУ = {str: "string", bool: "boolean", int: "integer", float: "number",
             list: "list", tuple: "list", type(None): "null"}


def причина_не_json(е):
    """`json.JSONDecodeError` → `invalid_json(line=L,col=C)`: місце обриву числами, без слів бібліотеки."""
    return "invalid_json(line=%d,col=%d)" % (е.lineno, е.colno)


def розбір(текст):
    """→ (обʼєкт, причина-код). Одна з двох завжди None.

    ЧОМУ ПРИЧИНА, А НЕ ЛИШЕ ПРОВАЛ. Це той самий урок, що вже полагоджено в
    `pipeline.паспорт_з_json` (Т-09, 11.09.2026): невдалий розбір без назви
    причини не давав другій спробі чого сказати моделі, і повторний виклик просив
    те саме тими самими словами, які вже не спрацювали.

    Т-02…Т-06 зносять `_json_у_рядки` і розбір усередині `паспорт_з_json` і
    кличуть цей — одна точка розбору на весь протокол.
    """
    т = str(текст or "").strip()
    if not т:
        return None, "empty_answer"
    # ПРОЗА ЗАМІСТЬ JSON — найчастіший провал, і він має зватись своїм кодом, а не
    # «Expecting value: line 1 column 1» від розбирача.
    if "{" not in т and not т.startswith("["):
        return None, "no_json_object(prose)"
    причина = None
    for сир in _кандидати(т):
        # ЛОВИМО ValueError, А НЕ Exception. `json.JSONDecodeError` — підклас
        # ValueError, а ширший except тут уже переодягнув NameError у «не JSON»
        # (спіймано пробою при першому ж прогоні): дефект коду виглядав як погана
        # відповідь моделі — рівно те, що СТАНДАРТ_КОДУ п. 14 забороняє робити на
        # живому шляху («виняток не ковтається без видимого сигналу споживачу»).
        try:
            об = _json_.loads(сир)
        except ValueError as e:
            причина = причина or (причина_не_json(e) if isinstance(e, _json_.JSONDecodeError)
                                  else "invalid_json")
            continue
        if isinstance(об, dict):
            return об, None
        return None, "json_not_object(%s)" % КОД_ТИПУ.get(type(об), type(об).__name__)
    return None, причина or "no_json_object"


def розібрати_json(текст):
    """→ обʼєкт або None. Скорочення Т-01 над `розбір`, коли причина не потрібна."""
    return розбір(текст)[0]


