def обʼєкт_помилки(помилки, відповідь=None):
    """Помилки → обʼєкт для повторного виклику (§1(б): один повторний, потім відмова).

    `помилки` — список від `перевірити` АБО рядок-причина від `розбір`: обидва
    провали формату їдуть одним каналом, інакше кожен викликач вигадав би собі
    другий. Обʼєкт потрібен і мосту (в діагноз відмови й журнал), і промпту
    (`помилка_формату` — той самий обʼєкт текстом), тож він тут один.
    """
    if isinstance(помилки, str):
        помилки = [_пом("", помилки)]
    о = dict(версія=ВЕРСІЯ, помилка="формат",
             помилки=[dict(де=п.get("де"), що=п.get("що")) for п in (помилки or [])])
    if відповідь:
        о["відповідь"] = відповідь
        о["натомість"] = ("Віддай ЛИШЕ один JSON-обʼєкт за схемою «%s», без пояснень "
                          "і без ```." % відповідь)
    else:
        о["натомість"] = "Віддай ЛИШЕ один JSON-обʼєкт, без пояснень і без ```."
    return о


def помилка_формату(помилки, відповідь=None):
    """Те саме рядком JSON — рівно те, що вкладається в повторний виклик."""
    return _json_.dumps(обʼєкт_помилки(помилки, відповідь), ensure_ascii=False)


