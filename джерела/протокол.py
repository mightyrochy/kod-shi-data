ТЕМПЕРАТУРА_КЛАСИ = ("тепла", "холодна", "нейтральна", "оливкова", "не_стверджується")

# ДЖЕРЕЛО ТЕМПЕРАТУРИ: три слова з Т-01. `palette.температура` віддає
