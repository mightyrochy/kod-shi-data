    вих, стек, позиції = [], [], []
    у_рядку = екр = False
    точка, ком, зек, дуж = None, 0, 0, 0
    пропущено_ком = зайвих_ком = лапок = хвостів = ключів = списків = обʼєктів = зайвих_закривних = відкривних = 0
    пропуск = 0
