# ІМЕНА СХЕМ ПО НАПРЯМКАХ. Поле `завдання.відповідь` мусить називати схему, яка
# справді існує, — enum над цим переліком це й перевіряє.
ДО_МОДЕЛІ = ("ПАКЕТ_V1", "ВЕРДИКТ_V1", "ОПИС_V1")
ВІД_МОДЕЛІ = ("ОБРАЗИ_V1", "ВИБІР_V1", "ОПИС_ВІДПОВІДЬ_V1")

ВЕРСІЯ = "1"


# ── ВАЛІДАТОР ────────────────────────────────────────────────────────────────
_ІМЕНА_ТИПІВ = {str: "рядок", bool: "логічне", int: "ціле", float: "число",
                list: "список", tuple: "список", dict: "обʼєкт", type(None): "порожнє"}


def _як_звати(v):
    """Тип значення словом для повідомлення про розходження — з `_ІМЕНА_ТИПІВ`,
    інакше питоняче імʼя типу."""
    return _ІМЕНА_ТИПІВ.get(type(v), type(v).__name__)


def _пом(шлях, що):
    """Одне розходження схеми: де воно й що саме. Порожній шлях — «корінь»."""
    return dict(де=шлях or "корінь", що=що)


def _нижче(шлях, ключ):
    """Шлях на рівень нижче: «людина» + «тіло» → «людина.тіло»."""
    return ключ if not шлях else "%s.%s" % (шлях, ключ)


def перевірити(схема, об, шлях=""):
    """→ список помилок `{де, що}`. Порожній список = обʼєкт відповідає схемі.

    Помилки збираються ВСІ, а не перша: повторний виклик до моделі має сенс лише
    тоді, коли називає все, що не так (§1(б) — один повторний виклик, далі чесна
    відмова). Зупинка на першій помилці дала б три виклики там, де досить одного.

    Зламана СХЕМА — це ValueError, а не запис у списку помилок. Дефект коду і
    дефект даних не мають права їхати одним каналом: інакше `завдання.відповідь`
    із друкарською помилкою в самій схемі виглядав би як «модель не тримає формат».
    """
    вузол = схема if isinstance(схема, dict) else None
    if вузол is None or вузол.get("тип") not in ТИПИ:
        raise ValueError("схема зламана: невідомий тип «%s» у «%s»"
                         % ((вузол or {}).get("тип"), шлях or "корінь"))
    т = вузол["тип"]
    if об is None:
        return [] if вузол.get("нуль") else [_пом(шлях, "порожнє (null), а схема тут його не дозволяє")]
    if т == "будь_що":
        return []
    # ── СКАЛЯРИ ──────────────────────────────────────────────────────────────
    if т in ("рядок", "число", "ціле", "логічне"):
        ок = {"рядок": lambda v: isinstance(v, str),
              # bool — підклас int у Python: без явного відсіву `True` пройшов би
              # як ціле, і «ітерація: true» стало б валідним вердиктом
              "ціле": lambda v: isinstance(v, int) and not isinstance(v, bool),
              "число": lambda v: isinstance(v, (int, float)) and not isinstance(v, bool),
              "логічне": lambda v: isinstance(v, bool)}[т](об)
        if not ок:
            return [_пом(шлях, "тип «%s», а треба «%s»" % (_як_звати(об), т))]
        # enum — ПІСЛЯ типу: «не той тип» не має перетворюватись у «не те значення»
        якщо_перелік = вузол.get("значення")
        if якщо_перелік and об not in якщо_перелік:
            return [_пом(шлях, "«%s» — не з переліку: %s"
                         % (об, ", ".join(str(z) for z in якщо_перелік)))]
        return []
    # ── СПИСОК ───────────────────────────────────────────────────────────────
    if т == "список":
        # tuple приймається разом зі list: код будує пакет кортежами
        # (`pipeline.пакет_для_моделі`: `слоти_альт=tuple(...)`), а `json.dumps`
        # робить із них масив. Валідувати можна і до, і після dumps.
        if not isinstance(об, (list, tuple)):
            return [_пом(шлях, "тип «%s», а треба «список»" % _як_звати(об))]
        пом = []
        if вузол.get("мін") is not None and len(об) < вузол["мін"]:
            пом.append(_пом(шлях, "у списку %d, а треба щонайменше %d" % (len(об), вузол["мін"])))
        if вузол.get("макс") is not None and len(об) > вузол["макс"]:
            пом.append(_пом(шлях, "у списку %d, а більше за %d не можна" % (len(об), вузол["макс"])))
        for i, x in enumerate(об):
            пом += перевірити(вузол["елемент"], x, "%s[%d]" % (шлях, i))
        return пом
    # ── КАРТА ────────────────────────────────────────────────────────────────
    if т == "карта":
        if not isinstance(об, dict):
            return [_пом(шлях, "тип «%s», а треба «обʼєкт» (карта за ключем)" % _як_звати(об))]
        пом = []
        for k in sorted(об, key=str):          # sorted → порядок помилок стабільний
            if not isinstance(k, str):
                пом.append(_пом(шлях, "ключ «%s» не рядок" % k))
                continue
            пом += перевірити(вузол["по_ключу"], об[k], _нижче(шлях, k))
        return пом
    # ── ОБʼЄКТ ───────────────────────────────────────────────────────────────
    if not isinstance(об, dict):
        return [_пом(шлях, "тип «%s», а треба «обʼєкт»" % _як_звати(об))]
    пом = []
    for k in вузол["треба"]:
        if k not in об:
            пом.append(_пом(_нижче(шлях, k), "ключа нема, а він обовʼязковий"))
    for k, в in вузол["поля"].items():
        if k in об:
            пом += перевірити(в, об[k], _нижче(шлях, k))
    return пом


