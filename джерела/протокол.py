_ПЕРЕД_СУДОМ = ("версія", "ітерація", "випадок", "день")


def _чекліст_на_дріт(чекліст):
    """Чекліст образу для моделі: провали, лічба і неперевірені пункти — КОДАМИ пунктів.

    `вимкнено[].бракує` (чого бракувало коду, щоб перевірити пункт) на дріт не їде: для
    моделі це не дія, а пояснення «чому» (правило власника 25.09 — у промпті лише роль,
    вхід, схема й межі), а на seed13_07/08 воно займало 16–17 % промпта ремонту. Звіт
    власника читає обʼєкт коду — там воно лишається.

    ВМ-2 (01.10.2026, рядок 483, аудит/ПРОДУКТ.md п.12): пункт їде КОДОМ (`внутрішня_мова.ЧЕКЛІСТ_КОДИ`),
    а не українським іменем; що код означає і з яких правил він, модель читає в словнику
    виклику (`task.statement_codes`). Пункт без ід (старий вердикт) — іменем, як доти."""
    if not isinstance(чекліст, dict):
        return чекліст

    def _код(ід, імʼя):
        return _ВМ.код_пункту(ід) or імʼя

    вих = {}
    for бік, п in чекліст.items():
        if not isinstance(п, dict):
            вих[бік] = п
            continue
        п = dict(п)
        ід = п.pop("провал_ід", None)
        if isinstance(ід, list) and isinstance(п.get("провал"), list) and len(ід) == len(п["провал"]):
            п["провал"] = [_код(і, н) for і, н in zip(ід, п["провал"])]
        if isinstance(п.get("вимкнено"), list):
            п["вимкнено"] = [(_код(х.get("пункт"), х.get("що")) if isinstance(х, dict) else х)
                             for х in п["вимкнено"]]
        вих[бік] = п
    return вих


# ── РІЧ БІЛЯ НОМЕРА — СКРІЗЬ, А НЕ ЛИШЕ У СКЛАДІ ОБРАЗУ (розбір 3/8, вада 1) ─
# ЩО БУЛО. `_твій_образ_на_дріт` дав опис речам СКЛАДУ, а суд над образом ішов
# далі самими номерами: у промпті ремонту прогону власника 25.09 — 211 голих
# «#N·MM» (208 із них у `знахідки[].речі`) і 14 СИРИХ id крамниць
# («ж-02220@honchstudio.com» усередині `суть` і `ремонт`), у промпті вибору —
# 107 і 2. Модель бачила «знято #2·15» і не мала способу дізнатись, про яку річ
# ідеться: пулу складання вона в цих викликах не бачить (свіжий контекст).
# ЩО ТЕПЕР. Рішення власника: «речі, які отримує функціональна модель, — завжди
# з повним описом». Номер лишається ІДЕНТИФІКАТОРОМ і живе в полі (`речі` стають
# обʼєктами `{н, назва, …}`, тими самими, що в пулі), а в РЕЧЕННІ на його місці
# стоїть назва речі — число-ідентифікатор у тексті модель однаково не резолвить.
# Місце речі в образі не прописується (те саме рішення власника): слоту тут нема.
# Сирий id крамниці до цього шару вже не доходить — його міняє на номер
# `вердикт_моделі.знахідки_вердикту`, де нумерація пулу й лежить.
_НОМЕР_У_ТЕКСТІ = _re.compile(r"#\d+·\d\d(?:/[^\s,;.»\"']+)?")
# `н` і `ід` — самі ідентифікатори: у них номер мусить лишитись номером.
_КЛЮЧІ_ІДЕНТИФІКАТОРІВ = frozenset({"н", "ід", "знахідка", "правило", "код"})


def _база_номера(н):
    """«#412·29/верх» → «#412·29»: половина комплекту описується тією самою річчю."""
    return str(н or "").split("/")[0]


def _мапа_описів(вердикт):
    """номер речі → її опис У ЦЬОМУ Ж вердикті: склади образів плюс вітрина.

    Інших джерел тут нема навмисно: опис має бути тим самим рядком, який модель
    бачить у вході, інакше вона читала б дві різні речі під одним номером."""
    м = {}
    for о in (вердикт.get("образи") or []):
        if not isinstance(о, dict):
            continue
        речі, оп = о.get("речі"), о.get("описи")
        if isinstance(речі, list) and isinstance(оп, list) and len(оп) == len(речі):
            for н, д in zip(речі, оп):
                if isinstance(д, dict) and д.get("назва"):
                    м.setdefault(_база_номера(н), д)
    for рч in (вердикт.get("вітрина") or {}).values():
        for r in (рч or []):
            if isinstance(r, dict) and r.get("н") and r.get("назва"):
                м.setdefault(_база_номера(r["н"]), r)
    return м


def _словами(текст, мапа):
    """Номер речі в РЕЧЕННІ — назвою тієї самої речі; номера, якого нема в мапі, не чіпаємо."""
    def _з(м):
        д = мапа.get(_база_номера(м.group(0)))
        return ("«%s»" % д["назва"]) if д else м.group(0)
    return _НОМЕР_У_ТЕКСТІ.sub(_з, текст)


# ЧОМУ В СУДІ — НОМЕР І НАЗВА, А НЕ ВЕСЬ ОПИС. Повний опис КОЖНОЇ речі образу вже
# стоїть у `твій_образ.речі` того самого судження, за кілька рядків вище; знахідка
# посилається на ту саму річ, і другий повний опис на кожну з 208 згадок — це
# копія, а не опис. Виміряно `проби/шлях_розмір_ремонт_gemma.py` на каталозі:
# повним обʼєктом промпт ремонту важить 149 778 символів ≈ 66 273 токени, тобто
# ПОНАД контекст ноутбукової gemma-4-12b (61 440) — ремонт просто не влазить;
# номером і назвою — у виміряній смузі сирих прогонів.
_ПОЛЯ_РЕЧІ_СУДУ = ("н", "назва")


def _річ_обʼєктом(н, мапа):
    """Номер речі → `{н, назва}`; річ поза вердиктом лишається номером (чесно)."""
    д = мапа.get(_база_номера(н))
    return (dict({к: д[к] for к in _ПОЛЯ_РЕЧІ_СУДУ if к in д}, н=str(н)) if д else str(н))


def _суд_на_дріт(вузол, мапа, ключ=None):
    """Суд над образом (знахідки, виконання, свідомі, структура, чекліст, вузол) з описами."""
    if isinstance(вузол, dict):
        вих = {}
        for к, v in вузол.items():
            if к == "речі" and isinstance(v, list):
                вих[к] = [_річ_обʼєктом(r, мапа) if isinstance(r, str) else _суд_на_дріт(r, мапа, к)
                          for r in v]
            elif к == "річ" and isinstance(v, str):
                вих[к] = _річ_обʼєктом(v, мапа)
            else:
                вих[к] = _суд_на_дріт(v, мапа, к)
        return вих
    if isinstance(вузол, list):
        return [_суд_на_дріт(v, мапа, ключ) for v in вузол]
    if isinstance(вузол, str) and ключ not in _КЛЮЧІ_ІДЕНТИФІКАТОРІВ:
        return _словами(вузол, мапа)
    return вузол


def _твій_образ_на_дріт(о):
    """Склад образу для моделі: кожна річ — її номер і опис, такий самий, як у пулі.

    У «твій_образ.речі» стояли самі номери, а назва речі — за 90 тис. символів від них, у
    пулі складання, якого ремонт не бачить. gemma (s13, 25.09) підписала всі 25 речей
    «#н/слот» навмання, за місцем у списку: 12 хибних (джинси «/верх», берет «/сумка»), і
    прибрала справжню сумку, бо вважала слот зайнятим. Тепер річ їде обʼєктом `{н, назва,
    тип…}`: `н` — той самий номер, що в «речі» (з половиною комплекту, якщо вона є), решта —
    `пакет_моделі._річ_пулу` цієї речі. Слоту тут нема: що джинси — низ, модель знає сама,
    а слоти веде код. Розбір відповіді читає номер і з такого обʼєкта, тож копія складу —
    той самий образ."""
    т = {к: о[к] for к in ПОЛЯ_ТВОГО_ОБРАЗУ if к in о}
    речі, оп = т.get("речі"), о.get("описи")
    if isinstance(речі, list) and isinstance(оп, list) and len(оп) == len(речі):
        т["речі"] = [dict({"н": н}, **{к: v for к, v in (д if isinstance(д, dict) else {}).items() if к != "н"})
                     for н, д in zip(речі, оп)]
    return т


def вердикт_на_дріт(вердикт):
    """ВЕРДИКТ_V1 обʼєктом коду → той самий вердикт у формі, яку читає модель.

    Обʼєкт без списку `образи` (повтор мови й будь-що інше) повертається як є:
    ехо там — саме те, чого просять («віддай ТОЙ САМИЙ обʼєкт»)."""
    if not isinstance(вердикт, dict) or not isinstance(вердикт.get("образи"), list):
        return вердикт
    мапа = _мапа_описів(вердикт)
    суд = [dict({ТВІЙ_ОБРАЗ: _твій_образ_на_дріт(о)},
                **{к: _суд_на_дріт(_чекліст_на_дріт(v) if к == "чекліст" else v, мапа, к)
                   for к, v in о.items() if к not in ПОЛЯ_ТВОГО_ОБРАЗУ and к != "описи"})
           for о in вердикт["образи"] if isinstance(о, dict)]
    вих = {к: v for к, v in вердикт.items() if к in _ПЕРЕД_СУДОМ}
    вих[ВЕРДИКТ_ОБРАЗІВ] = суд
    вих.update((к, v) for к, v in вердикт.items()
               if к not in _ПЕРЕД_СУДОМ and к not in ("образи", "завдання"))
    з = вердикт.get("завдання")
    if isinstance(з, dict):
        вих["завдання"] = {к: v for к, v in з.items() if к != "схема_відповіді"}
        if "схема_відповіді" in з:
            вих["завдання"]["схема_відповіді"] = з["схема_відповіді"]
    elif з is not None:
        вих["завдання"] = з
    return вих


