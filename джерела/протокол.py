def _зайва_закривна(т, i):
    """Від `т[i]` (поза рядком) перша дужка, що закриває глибше за початок, — «}» (а не «]» чи кінець тексту)."""
    г, n = 0, len(т)
    while i < n:
        с = т[i]
        if с == '"':
            i += 1
            while i < n and т[i] != '"':
                i += 2 if т[i] == "\\" else 1
        elif с in "{[":
            г += 1
        elif с in "}]":
            if not г:
                return с == "}"
            г -= 1
        i += 1
    return False


_ПЕРШИЙ_КЛЮЧ = _re.compile(r'\{\s*"((?:[^"\\]|\\.)*)"\s*:')


def _перший_ключ(т):
    """Перший ключ обʼєкта, яким починається `т` («{"ключ": …»), або None."""
    м = _ПЕРШИЙ_КЛЮЧ.match(т)
    return м.group(1) if м else None


def _ключ_від(т, i):
    """Рядок, що починається лапкою `т[i]`, коли він ключ (за закривною лапкою, пробіли не в лік, стоїть «:»), → його
    текст; інакше None."""
    k, n = i + 1, len(т)
    while k < n and т[k] != '"':
        k += 2 if т[k] == "\\" else 1
    j = k + 1
    while j < n and т[j].isspace():
        j += 1
    return т[i + 1:k] if j < n and т[j] == ":" else None


_КЛЮЧ_У_КІНЦІ = _re.compile(r'"((?:[^"\\]|\\.)*)"\s*:\s*$')


def _ключ_перед(т):
    """Ключ, за яким `т` скінчився («"ключ":»), або None."""
    м = _КЛЮЧ_У_КІНЦІ.search(т)
    return м.group(1) if м else None


def _ключі_сусіди(а, б):
    """Два різні ключі, що різняться лише числами («OUTFITS_V1» і «OUTFITS_V2»)."""
    return bool(а and б and а != б and _re.sub(r"\d+", "", а) == _re.sub(r"\d+", "", б))


