_У_ДУЖКАХ = _re.compile(r"```(?:json)?\s*(\{.*?\})\s*```", _re.S)


def _кандидати(т):
    """Три місця, де у відповіді моделі буває JSON, за спаданням явності.

    ЦІЛИЙ ТЕКСТ СТОЇТЬ ПЕРЕД ВИРІЗАННЯМ ПО ДУЖКАХ НАВМИСНО. Зріз «від першої `{`
    до останньої `}`» завжди починається з `{`, тобто завжди дає обʼєкт або
    провал розбору — і через це відповідь-МАСИВ (модель віддала сам список
    образів замість обʼєкта з полем `образи`) перетворювалась у ПЕРШИЙ образ, а
    решта девʼять зникали без жодного слова. Це рівно та тиха втрата, проти якої
    цей модуль і написаний. Тепер масив розбирається цілим і дістає імʼя
    («JSON, але не обʼєкт»), а зріз лишається останньою спробою для відповіді,
    обгорнутої прозою.
    """
    м = _У_ДУЖКАХ.search(т)
    if м:
        yield м.group(1)
    yield т
    a, b = т.find("{"), т.rfind("}")
    if a >= 0 and b > a and т[a:b + 1] != т:
        yield т[a:b + 1]


def розбір(текст):
    """→ (обʼєкт, причина). Одна з двох завжди None.

    ЧОМУ ПРИЧИНА, А НЕ ЛИШЕ ПРОВАЛ. Це той самий урок, що вже полагоджено в
    `pipeline.паспорт_з_json` (Т-09, 11.09.2026): невдалий розбір без назви
    причини не давав другій спробі чого сказати моделі, і повторний виклик просив
    те саме тими самими словами, які вже не спрацювали.

    Т-02…Т-06 зносять `_json_у_рядки` і розбір усередині `паспорт_з_json` і
    кличуть цей — одна точка розбору на весь протокол.
    """
    т = str(текст or "").strip()
    if not т:
        return None, "порожня відповідь"
    # ПРОЗА ЗАМІСТЬ JSON — найчастіший провал, і він має зватись своїм імʼям, а не
    # «Expecting value: line 1 column 1» від розбирача.
    if "{" not in т and not т.startswith("["):
        return None, "у відповіді нема JSON-обʼєкта (проза без дужок)"
    причина = None
    for сир in _кандидати(т):
        # ЛОВИМО ValueError, А НЕ Exception. `json.JSONDecodeError` — підклас
        # ValueError, а ширший except тут уже переодягнув NameError у «не JSON»
        # (спіймано пробою при першому ж прогоні): дефект коду виглядав як погана
        # відповідь моделі — рівно те, що СТАНДАРТ_КОДУ п. 14 забороняє робити на
        # живому шляху («виняток не ковтається без видимого сигналу споживачу»).
        try:
            об = _json_.loads(сир)
        except ValueError as e:
            причина = причина or "не JSON (%s)" % str(e)[:60]
            continue
        if isinstance(об, dict):
            return об, None
        return None, "JSON, але не обʼєкт (%s)" % _як_звати(об)
    return None, причина or "у відповіді нема JSON-обʼєкта"


def розібрати_json(текст):
    """→ обʼєкт або None. Скорочення Т-01 над `розбір`, коли причина не потрібна."""
    return розбір(текст)[0]


