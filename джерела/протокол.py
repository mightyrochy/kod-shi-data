# Вузол схеми — звичайний dict із ключем `тип`. Конструктори нижче потрібні не
# для краси: вони єдине місце, де форма вузла оголошена, тож `перевірити` може
# падати ValueError на зламаній схемі, не плутаючи її з поганими даними.
ТИПИ = ("обʼєкт", "карта", "список", "рядок", "число", "ціле", "логічне", "будь_що")

РЯДОК = dict(тип="рядок")
