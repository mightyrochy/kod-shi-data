# (qwen3.5-9b): рука 1 дала образ у 1 сценарії з 8. Більшість провалів — не в
# тому, що модель запропонувала, а в тому, як КОД поводився з неідеальною
# ФОРМОЮ: ключ «обрazi» з латинськими літерами, рядок там, де схема чекає
# список (і «Як це носити» розсипалось на літери), масив образів без обгортки,
# відповідь, що обірвалась об стелю виводу на десятому образі, — і дев'ять
# цілих образів ішли в смітник разом із недописаним. `розбір` лишається
# СУВОРИМ (його причину читає повторний виклик); цей шар стоїть над ним і
# читає те, що модель ОДНОЗНАЧНО мала на увазі, — і лише це.
# МЕЖА ОДНОЗНАЧНОСТІ, названа вголос: ключ перейменовується, лише коли він
# збігається з ОДНИМ оголошеним полем, якого в обʼєкті нема (літера за літерою,
# латиниця як двійник кирилиці); рядок стає списком лише там, де схема чекає
# список; з обрізаної відповіді беруться лише значення, що встигли закритись
# (цілий образ — так, недописаний — ні). Усе інше лишається помилкою формату з
# ОДНИМ повторним викликом, як доти (§1(б)). Кожна нормалізація називається
# рядком у `нотатки` — у звіт власника й діагноз, не мовчки.

# Кирилична літера → її латинські двійники: гомогліф (о/o, р/p, с/c) або
# транслітерація (з/z, и/i). Довгі (ш/sh) — окремо, бо це кілька символів.
_ЛАТ = {"а": "a", "б": "b", "в": "vbw", "г": "gh", "ґ": "g", "д": "d", "е": "e", "є": "e",
        "ж": "", "з": "z", "и": "iy", "і": "i", "ї": "i", "й": "ijy", "к": "k", "л": "l",
        "м": "m", "н": "nh", "о": "o", "п": "pn", "р": "rp", "с": "sc", "т": "t", "у": "uy",
        "ф": "f", "х": "hx", "ц": "c", "ч": "", "ш": "", "щ": "", "ь": "", "ю": "", "я": ""}
_ЛАТ_ДОВГІ = {"ж": ("zh",), "ч": ("ch",), "ш": ("sh",), "щ": ("shch", "sch"), "ю": ("yu", "iu"),
              "я": ("ya", "ia"), "є": ("ye", "ie"), "ї": ("yi", "ji"), "х": ("kh",), "ц": ("ts",)}


def _візерунок_ключа(поле):
    """Регекс, що впізнає ключ `поле`, написаний із латинськими двійниками літер,
    у будь-якому регістрі, з пробілом чи дефісом замість `_` і з будь-яким апострофом."""
    частини = []
    for с in поле.lower():
        if с == "_":
            частини.append(r"[_\s\-]")
        elif с in "ʼ'’":
            частини.append(r"[ʼ'’`]?")
        elif с == "ь":
            частини.append(r"(?:ь|')?")
        else:
            альт = [с] + list(_ЛАТ.get(с, "")) + list(_ЛАТ_ДОВГІ.get(с, ()))
            частини.append("(?:%s)" % "|".join(_re.escape(а) for а in альт))
    return _re.compile("^" + "".join(частини) + "$")


def _ключ_схеми(ключ, поля, об):
    """Оголошене поле, яке однозначно мав на увазі чужий ключ, або None.

    ОДНОЗНАЧНО = рівно одне поле схеми, якого в обʼєкті ще нема, і ключ збігається
    з ним літера за літерою з точністю до латинських двійників, регістру,
    пробілів і апострофа. Два кандидати — вгадувати не беремось."""
    к = str(ключ).strip().lower()
    збіги = [п for п in поля if п not in об and _візерунок_ключа(п).match(к)]
    return збіги[0] if len(збіги) == 1 else None


def _нормалізувати(вузол, об, шлях, нотатки):
    """Обʼєкт відповіді → той самий обʼєкт, приведений до схеми там, де намір
    однозначний. Кожна зміна — рядком у `нотатки`. Решту розходжень ловить
    `перевірити`, як і доти."""
    т = вузол.get("тип")
    де = шлях or "корінь"
    if т == "обʼєкт" and isinstance(об, dict):
        поля = вузол["поля"]
        for к in list(об):
            if к in поля:
                continue
            ціль = _ключ_схеми(к, поля, об)
            if ціль:
                об[ціль] = об.pop(к)
                нотатки.append("%s: ключ «%s» прочитано як «%s»" % (де, к, ціль))
        # ОБОВʼЯЗКОВЕ ПОЛЕ, ЯКЕ МОДЕЛЬ ВКЛАЛА НА РІВЕНЬ НИЖЧЕ ({"вибір": {"обрано": …}},
        # {"відповідь": {"текст": …}}): рівно один вкладений обʼєкт його несе — підняти.
        for к in вузол.get("треба", ()):
            if к in об:
                continue
            несуть = [(кл, з) for кл, з in об.items() if isinstance(з, dict)
                      and (к in з or _ключ_схеми_у(к, з))]
            if len(несуть) == 1:
                кл, з = несуть[0]
                for кз in list(з):
                    ціль = кз if кз in поля else _ключ_схеми(кз, поля, об)
                    if ціль and ціль not in об:
                        об[ціль] = з[кз]
                нотатки.append("%s: «%s» лежало всередині «%s» — піднято" % (де, к, кл))
        for к, в in поля.items():
            if к in об:
                об[к] = _нормалізувати(в, об[к], _нижче(шлях, к), нотатки)
        return об
    if т == "список":
        ел = вузол["елемент"]
        if isinstance(об, str):
            # РЯДОК ТАМ, ДЕ СХЕМА ЧЕКАЄ СПИСОК (З-1в): без цього рядок ітерувався
            # символами — «Як це носити» ставало шістьма літерами «К · у · р · т · к · у»,
            # а номер речі в «фото_не_те» гинув, розсипаний на «#», «8», «0».
            пункти = ([р.strip() for р in об.split("\n") if р.strip()]
                      if ел.get("тип") == "рядок" else [об]) if об.strip() else []
            нотатки.append("%s: рядок замість списку — прочитано як список з %d" % (де, len(пункти)))
            об = пункти
        elif isinstance(об, dict) and ел.get("тип") == "обʼєкт":
            нотатки.append("%s: один обʼєкт замість списку — прочитано як список з одного" % де)
            об = [об]
        if isinstance(об, list):
            return [_нормалізувати(ел, х, "%s[%d]" % (шлях, і), нотатки) for і, х in enumerate(об)]
        return об
    if т == "рядок" and not вузол.get("значення") and isinstance(об, list) and об \
            and all(isinstance(х, str) for х in об):
        # «текст»: ["абзац", "абзац"] — та сама проза, лише розбита на пункти
        нотатки.append("%s: список рядків замість рядка — склеєно по рядку" % де)
        return "\n".join(х.strip() for х in об if х.strip())
    return об


def _ключ_схеми_у(поле, з):
    """Чи несе обʼєкт `з` поле `поле` під латинським двійником імені."""
    return any(_візерунок_ключа(поле).match(str(к).strip().lower()) for к in з)


def _початки(т):
    """Де в тексті може починатись JSON: перша `{` і перша `[` (раніша — першою)."""
    п = sorted(i for i in (т.find("{"), т.find("[")) if i >= 0)
    return п


_ЗАКРИТТЯ = {"{": "}", "[": "]"}
# що JSON дозволяє після «\» у рядку
_ЕКРАНИ_JSON = frozenset('"\\/bfnrtu')


def _закрити(т):
    """JSON-текст із вадою ФОРМИ → (текст, що_зроблено) або None.

    Вади однозначні: закривна дужка не та, яку чекає стек поза рядками (ставиться та),
    «\\» перед не-екраном у рядку, кома перед дужкою (знімається) і ОБРИВ —
    відповідь скінчилась, а JSON ні (модель уперлась у стелю виводу). Обрив
    лікується відкатом до останньої межі значення, що встигло закритись на
    глибині ≤ 2, і закриттям відкритих дужок. Глибина 2 — це рівно «елемент
    списку в корені»: цілий образ у `образи` лишається, недописаний — ні; поле
    кореня (`обрано`, `текст`) лишається, лише якщо встигло закритись. Недописане
    НЕ дописується: образ на три речі з п'яти був би вже не тим образом.

    ЩЕ ТРИ ВАДИ ФОРМИ (Л-4, 26.09.2026) — ті, що лишились на gemma після #331 («решта 5
    вад — кома, обрив»), і з них розбір прози складав ОДИН образ з усіх номерів тексту
    (20–26 речей, 0 помилок схеми): кома між двома значеннями пропущена («} {») —
    ставиться; кома двічі поспіль або одразу після відкривної дужки — знімається; лапка
    посеред рядка, за якою не йде ні кома, ні дужка, ні двокрапка, ні інша лапка («сережки
    "Pearl" беж») — це символ тексту, а не кінець рядка, і він екранується. Кожна правка
    лічиться (`пропущено_ком`, `зайвих_ком`, `лапок`) і називається в `нормалізовано`."""
    вих, стек = [], []
    у_рядку = екр = False
    точка, ком, зек, дуж = None, 0, 0, 0
    пропущено_ком = зайвих_ком = лапок = 0
    # ОСТАННІЙ ЗНАЧУЩИЙ СИМВОЛ ПОЗА РЯДКОМ: «"» — рядок щойно закрився, буква чи
    # цифра — скінчився літерал (число, true/false/null). Після них нове значення
    # без коми — це кома, якої бракує.
    попер = None
    n = len(т)
    for i in range(n):
        с = т[i]
        if у_рядку:
            if екр and с not in _ЕКРАНИ_JSON:
                # «\» ПЕРЕД НЕ-ЕКРАНОМ (gemma, s13, 25.09: «…ансамбля.\⏎Жіноча сумка…»,
                # «тепло…\ Сумка») — вада форми, намір однозначний: «\» і справжній
                # перенос — це перенос («\n»), «\» перед будь-чим іншим знімається.
                вих.pop()
                вих.append("\\n" if с == "\n" else с)
                екр, зек = False, зек + 1
                continue
            if екр:
                вих.append(с)
                екр = False
                continue
            if с == "\\":
                вих.append(с)
                екр = True
                continue
            if с == '"':
                j = i + 1
                while j < n and т[j].isspace():
                    j += 1
                if j < n and т[j] not in ',}]:"':
                    вих.append('\\"')
                    лапок += 1
                    continue
                вих.append(с)
                у_рядку = False
                попер = '"'
                continue
            вих.append(с)
            continue
        if с.isspace():
            вих.append(с)
            continue
        if с in '{["' and стек and (попер in ('}', ']', '"') or (попер or "").isalnum()):
            вих.append(",")
            пропущено_ком += 1
            if len(стек) <= 2:
                точка = (len(вих), tuple(стек))
        if с == '"':
            у_рядку = True
        elif с in "{[":
            стек.append(с)
        elif с in "}]":
            j = len(вих) - 1
            while j >= 0 and вих[j].isspace():
                j -= 1
            if j >= 0 and вих[j] == ",":
                del вих[j]
                ком += 1
            if not стек:
                return None
            if _ЗАКРИТТЯ[стек[-1]] != с:
                # ЗАКРИВНА НЕ ТА (gemma, розкид #329, 25.09: останній образ закрито «]» замість
                # «}» — 7 із 10 невалідних відповідей складання й ремонту): стек поза рядками
                # однозначно каже, яка дужка тут закривається, — ставиться вона.
                с = _ЗАКРИТТЯ[стек[-1]]
                дуж += 1
            стек.pop()
            вих.append(с)
            попер = с
            if not стек:
                return "".join(вих), dict(ком=ком, зек=зек, дуж=дуж, обрізано=False,
                                          пропущено_ком=пропущено_ком, зайвих_ком=зайвих_ком,
                                          лапок=лапок)
            if len(стек) <= 2:
                точка = (len(вих), tuple(стек))
            continue
        elif с == ",":
            if попер in (",", "[", "{", None):
                зайвих_ком += 1
                continue
            if стек and len(стек) <= 2:
                точка = (len(вих), tuple(стек))
        вих.append(с)
        попер = с
    if not стек or точка is None:
        return None
    довж, ст = точка
    return ("".join(вих[:довж]).rstrip().rstrip(",")
            + "".join(_ЗАКРИТТЯ[с] for с in reversed(ст))), dict(ком=ком, зек=зек, дуж=дуж, обрізано=True,
                                                                  пропущено_ком=пропущено_ком,
                                                                  зайвих_ком=зайвих_ком, лапок=лапок)


def розбір_за_схемою(текст, схема):
    """→ (обʼєкт, причина, нотатки): `розбір` плюс прочитання однозначного наміру.

    `схема` — імʼя з `СХЕМИ` («ОБРАЗИ_V1», «ВИБІР_V1», «ОПИС_ВІДПОВІДЬ_V1»).
    `нотатки` = {`нормалізовано`: [рядок на кожну зміну], `обрізано`: True, коли
    JSON обірвався й узято цілі значення до обриву, `ехо`: [{де, що}] — для
    ОБРАЗИ_V1 образи, переписані з вхідного вердикта (Т-7, `_без_ехо`): з обʼєкта
    їх знято, і кожен названо}. Порожні нотатки — відповідь прочитано як є, тобто
    рівно те, що дав би `розбір`.

    Порядок: спершу суворий `розбір` (його успіх лишається байт-у-байт тим
    самим); лише на його провалі — ремонт форми (`_закрити`) і JSON без суворості
    до сирих переносів у рядках (`strict=False`: модель пише абзаци прози
    справжнім переносом, а не `\\n`); масив там, де схема чекає обʼєкт, — одним
    обʼєктом (якщо він один) або, для ОБРАЗИ_V1, списком образів. Далі —
    `_нормалізувати` за схемою. Невдача ремонту віддає причину СУВОРОГО розбору:
    її й читає повторний виклик."""
    вузол = СХЕМИ[схема]
    нотатки = dict(нормалізовано=[], обрізано=False, ехо=[])
    об, причина = розбір(текст)
    т = str(текст or "")
    if об is None:
        for поч in _початки(т):
            р = _закрити(т[поч:])
            if not р:
                continue
            сир, що = р
            try:
                знайдено = _json_.loads(сир)
            except ValueError:
                try:
                    знайдено = _json_.loads(сир, strict=False)
                except ValueError:
                    continue
                нотатки["нормалізовано"].append(
                    "корінь: сирий перенос рядка всередині тексту JSON — прочитано як перенос")
            if isinstance(знайдено, list):
                словники = [х for х in знайдено if isinstance(х, dict)]
                if схема == "ОБРАЗИ_V1" and словники and len(словники) == len(знайдено):
                    знайдено = dict(образи=знайдено)
                    нотатки["нормалізовано"].append(
                        "корінь: масив образів без обгортки {версія, образи} — прочитано як «образи»")
