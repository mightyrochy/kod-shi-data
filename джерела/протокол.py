# Код адресує образ «о1», знахідку «з-о1-1» / «з-набір-1», блокер «б-о1-1» — кирилицею, і ці ід
# стоять у звіті, журналі й пробах. Модель бачить їх у промптах ремонту й вибору й пише назад
# («finding», «chosen», «id»). На дроті вони латинкою — «o1», «f-o1-1», «f-set-1», «b-o1-1»
# (`ід_на_дріт`, обхід дроту вердикта); розбір відповіді повертає їх до ід коду (`ід_з_дроту`)
# у тих самих полях, тож усе за розбором бачить ті самі ід, що доти. Рядок, що не є ід коду
# точно, не чіпається — і назва речі, і чужий ід моделі («образ_1») лишаються як є.
_ІД_НА_ДРІТ = _re.compile(r"^(?:([зб])-)?(?:о(\d+)|(набір))(?:-(\d+))?$")
_ІД_З_ДРОТУ = _re.compile(r"^(?:([fb])-)?(?:o(\d+)|(set))(?:-(\d+))?$")
_ПОЛЯ_ІД = ("ід", "знахідка", "обрано")


def _ід(м, вид, образ, набір):
    """Зібрати ід з частин збігу: вид («з»/«б» чи «f»/«b»), номер образу або набір, номер."""
    if not м or (м.group(1) is None) != (м.group(4) is None) or (м.group(3) and not м.group(1)):
        return None
    тіло = (образ + м.group(2)) if м.group(2) else набір
    return тіло if not м.group(1) else "%s-%s-%s" % (вид[м.group(1)], тіло, м.group(4))


def ід_на_дріт(v):
    """Ід коду («о1», «з-о1-1», «з-набір-1», «б-о1-1») → ід дроту латинкою; інше — як є."""
    if not isinstance(v, str):
        return v
    return _ід(_ІД_НА_ДРІТ.match(v), {"з": "f", "б": "b"}, "o", "set") or v


def ід_з_дроту(v):
    """Ід дроту («o1», «f-o1-1», «f-set-1», «b-o1-1») → ід коду; інше — як є."""
    if not isinstance(v, str):
        return v
    return _ід(_ІД_З_ДРОТУ.match(v.strip()), {"f": "з", "b": "б"}, "о", "набір") or v


def ід_на_дріт_усюди(в):
    """Те саме над усім деревом дроту: кожен рядок, що є ід коду точно, — латинкою."""
    if isinstance(в, dict):
        return {к: ід_на_дріт_усюди(v) for к, v in в.items()}
    if isinstance(в, list):
        return [ід_на_дріт_усюди(v) for v in в]
    return ід_на_дріт(в)


