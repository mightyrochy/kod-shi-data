_ПОРЯДОК = [nm for nm, _ in ПС.areas.РІВНІ]        # згори вниз


def _інтерполяція(проф, рівень):
    """Значення профілю на рівні: між заданими — лінійно за індексом рівня, поза —
    крайнім значенням."""
    задані = sorted((_ПОРЯДОК.index(k), v) for k, v in проф.items() if k in _ПОРЯДОК)
    if not задані or рівень not in _ПОРЯДОК: return None
    i = _ПОРЯДОК.index(рівень)
    if i <= задані[0][0]: return задані[0][1]
    if i >= задані[-1][0]: return задані[-1][1]
    for (a, va), (b, vb) in zip(задані, задані[1:]):
        if a <= i <= b:
            return va + (vb - va) * ((i - a) / (b - a) if b != a else 0.0)
    return задані[-1][1]


def ширина_крою(крій, рівень, ширина_тіла_на, обхвати_виробу=None, обхвати_тіла=None):
    """Ширина виробу на рівні. `ширина_тіла_на` — функція рівень -> ширина тіла.

    Вимір перекриває таблицю: якщо в SKU є обхват виробу на цьому рівні, ширина
    рахується з нього (обхват/π, як і тіло в areas). Це названий шлях від T3 до T1,
    і він вмикається сам, щойно у фіді з'являються числа розмірної сітки."""
    if обхвати_виробу and рівень in обхвати_виробу:
        return float(обхвати_виробу[рівень]) / math.pi, "вимір розмірної сітки"
    к = КРОЇ.get(крій)
    if not к: return None, "крій невідомий"
    if к["рід"] == "прилягає":
        e = _інтерполяція(к["ease"], рівень)
        w = ширина_тіла_на(рівень)
        return (None, "рівень невідомий") if (e is None or w is None) else \
               (w * e, "таблиця: прилягає")
    # ВІДХОДИТЬ: нижче бази ширину задає виріб
    база = к["база"]
    w_бази = ширина_тіла_на(база)
    if w_бази is None: return None, "нема бази"
    w_бази *= к["припуск_бази"]
    i_база, i = _ПОРЯДОК.index(база), _ПОРЯДОК.index(рівень)
    if i < i_база:
        # НАД базою тіло ще тримає річ: плече оверсайзу ширше за плече, але НЕ на 40%.
        # Без цієї гілки плечі отримували припуск грудей (1.40), і образ «оверсайз +
        # широкі» діставав фальшивий відліт угорі.
        w = ширина_тіла_на(рівень)
        e = _інтерполяція(к.get("над") or {}, рівень)
        if e is None: e = 1.0 + (к["припуск_бази"] - 1.0) * 0.35   # T3: третина припуску
        return (None, "рівень невідомий") if w is None else (w * e, "таблиця: над базою")
    f = _інтерполяція(к["форма"], рівень)
    return (None, "форма не задана") if f is None else \
           (w_бази * f, "таблиця: відходить від «%s»" % база)


