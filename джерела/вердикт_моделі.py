    # ── ПЕРЕПИС ФОТО НЕ БАЧИТЬ, І ЦЕ СКАЗАНО ВГОЛОС (рядок 44 дошки) ─────────
    # Перепис мови йде БЕЗ знімків (`показ.html`: «двадцять знімків удруге
    # коштують рівно стільки ж»), а «віддай ТОЙ САМИЙ обʼєкт» разом зі схемою
    # `ОПИС_ВІДПОВІДЬ_V1` просить заповнити й `фото_не_те` — тобто свідчення про
    # те, чого моделі не показали. Звідси позначка «фото крамниці може не
    # відповідати назві» на речах, чиє фото збігається. Межу тримає код
