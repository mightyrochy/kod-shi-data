    зап = [(i, о) for i, о in enumerate(_образи_суду(образи), 1)
           if isinstance(о, dict) and (о.get("речі") or о.get("речі_н"))]
    if not зап:
        return None
    ід = [_ід_образу(о, i) for i, о in зап]
    об = [о for _, о in зап]
    вих, зн = {}, []
    # ── ОДИН І ТОЙ САМИЙ СЛОТ НА ВЕСЬ НАБІР (K-VAR-01, 18.09.2026) ───────────
    # ЩО БУЛО ЗЛАМАНО. Ребро «варіанти одного» — це Jaccard пари АБО (та сама
    # схема І той самий герой). Десять образів, у яких різні сукня, сумка й
    # прикраси, а взуття одне, дають Jaccard 1/9 = 0.11 при порозі 0.6, різні
    # схеми й різних героїв — тобто жодного ребра. Виміряно на живому шляху
    # (`проби/vzuttia_руки.py`, каталог_повний, «побачення · ресторан · 19:00»):
    # десять образів на ОДНІЙ парі давали `ок=true`, «усі 10 образів різні» і
    # нуль знахідок набору. Набір, у якому взуття не вибирають, оголошувався
    # вибором — рівно те, що тема-4 XIII зве вибором на вигляд.
    # ЧОМУ ЦЕ ГРУПА, А НЕ ОКРЕМА ЗНАХІДКА. `знахідки_вердикту` зливає знахідки
    # одного правила в ОДИН рядок із найсильнішої (Н-P37), тож другий K-VAR-01
    # тут загубив би свою суть щоразу, коли поруч є група за Jaccard. Отже це
    # той самий предмет тим самим правилом: перелік образів, які між собою не
    # вибір, і причина в рядку `чому`.
    повтори = _повтор_слота(об, ід)
    if len(об) >= 2:
        поріг = _РЕЄСТР.C["jaccard_варіанта"]
        сусіди = {i: set() for i in range(len(об))}
        пари = {}
        for i in range(len(об)):
            for j in range(i + 1, len(об)):
                п = пари[(i, j)] = _пара_образів(об[i], об[j])
                if п["jaccard"] >= поріг or (п["схема"] and п["герой"]):
                    сусіди[i].add(j)
                    сусіди[j].add(i)
        групи, бачені = [], set()
        for i in range(len(об)):
            if i in бачені or not сусіди[i]:
                continue
            стек, компонента = [i], []
            while стек:
                k = стек.pop()
                if k in бачені:
                    continue
                бачені.add(k)
                компонента.append(k)
                стек += [x for x in сусіди[k] if x not in бачені]
            if len(компонента) > 1:
                групи.append(sorted(компонента))
        чому = [_чому_група([ід[i] for i in г],
                            [пари[(min(a, b), max(a, b))] for a in г for b in г if a < b])
                for г in групи]
        всі_групи = [[ід[i] for i in г] for г in групи] + [п["образи"] for п in повтори]
        чому = чому + [п["чому"] for п in повтори]
        вих["різноманітність"] = dict(
            ок=not всі_групи, групи=всі_групи,
            чому=("; ".join(чому) if чому
                  else "усі %d %s різні: жодна пара не збіглася ні складом, ні схемою "
                       "з героєм%s" % (len(об), _множина(len(об), "образ", "образи",
                                                         "образів"),
                                       "" if any(о.get("слоти_н") for о in об)
                                       else "; повтор речі в слоті НЕ перевірявся — "
                                            "у записах образів нема слотів речей")))
        # «БЕЗ ВХОДУ» ЇДЕ ПОРУЧ ІЗ ВИСНОВКОМ, А НЕ ЗАМІСТЬ НЬОГО. Літера силуету —
        # одна з трьох ознак, якими Т-10 порівнює образи; коли вона рахована без
        # частини речей, порівняння мусить сказати це тим самим рядком `чому`, яким
        # воно вже каже «повтор речі в слоті НЕ перевірявся — у записах образів
        # нема слотів речей». Інакше збіг літер двох образів виглядав би виміром,
        # а був би збігом того, чого в обох не порахували.
        _бд = sorted({р for о in об if isinstance(о.get("риси"), dict)
                      for р in (о["риси"].get("літера_без_довжини") or ())})
