def _питання_або_нуль(z):
    """Знахідка без виміру: регістр «питання» (дефолтний крій, невідома довжина,
    не виміряний баланс) або сила 0/None. Це запити на дані, не зауваження.

    Переїхала сюди з `bridge` (Т-03): тепер її читає `знахідки_вердикту`, а
    `bridge` імпортує `pipeline`, не навпаки — другої копії бути не може."""
    if z.get("сила") == "питання" or z.get("регістр") == "питання":
        return True
    # «тут не вирішує нічого / нема що сказати» — це відсутність знахідки, не знахідка
    # (K-SHO-07 давав такий рядок на 85 % образів у чотирьох сценаріях, 05.09)
    if _re_ід.search(r"не вирішує нічого|нема що сказати|не впливає тут|нічого не змінює",
                     str(z.get("суть") or ""), _re_ід.I):
        return True
    нп = z.get("сила_нп")
    try:
        return нп is None or float(нп) <= 0.0
    except (TypeError, ValueError):
        return True


# Ім'я ПОЛЯ в лапках («устілка_см», «довжина_стопи_мм») — підкреслення тут і є
# розрізнювачем: назва речі в лапках («Сумка жіноча Sack») його не має, а поле
# картки чи виміру людини без нього не пишеться ніде в корпусі.
_ПОЛЕ_У_ПИТАННІ = r"[«\"']([a-zа-яіїєґ0-9]+(?:_[a-zа-яіїєґ0-9]+)+)[»\"']"


def вага_питання(z):
    """Наскільки питання адресне: 3 — названо і річ, і поле; 2 — лише річ;
    1 — лише поле; 0 — загальне. Ключ сортування черги на вхід (більше — раніше).

    ЩО ЦЕ МІНЯЄ В РІШЕННІ (рядок 19 дошки, РВ-4 З-3). `bridge` ріже питання на
    12, а показ бере з них ПЕРШІ П'ЯТЬ — у діагноз екрана і в колонку
    `питання_коду` журналу. Порядок доти був порядком народження знахідок, і на
    образі з восьми речей до жінки доїжджали «площі не виміряні» та сім
    однакових «входу нема», а K-SHO-13 («вимір людини "довжина_стопи_мм", поле
    речі "устілка_см"») і K-HAT-01 не влазили навіть у дванадцять. Тобто з
    черги на вхід було видно рівно те, чого доміряти не може ніхто, і не видно
    того, що закривається одним полем картки.

    Обидва розрізнювачі — про АДРЕСУ, не про важливість:
    · названа річ — `речі` непорожні й це не службове «образ» (ним позначають
      себе записи `БЕЗ_ВХОДУ`: вони від речей не залежать за побудовою);
    · назване поле — у `суть` стоїть ім'я поля, а не назва речі.
    Сила тут не важить навмисно: у питань її нема — вони й є ті рядки, у яких
    вимір відсутній (`_питання_або_нуль`)."""
    речі = [str(r) for r in (z.get("речі") or []) if str(r or "").strip()]
    названа_річ = bool(речі) and речі != ["образ"]
    назване_поле = bool(_re_ід.search(_ПОЛЕ_У_ПИТАННІ, str(z.get("суть") or "")))
    return (2 if названа_річ else 0) + (1 if назване_поле else 0)


