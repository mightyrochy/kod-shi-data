def _у_лапках(т):
    """Усі «…» з рядка по порядку — слоти, які `структура_образу` називає в лапках."""
    out, i = [], 0
    while True:
        a = т.find("«", i)
        b = т.find("»", a + 1) if a >= 0 else -1
        if b < 0:
            return out
        out.append(т[a + 1:b])
        i = b + 1


def номер_речі(ід, ном=None, частина=None):
    """«#N·MM» з нумерації пулу (той самий номер, що бачила модель); річ поза пулом —
    своїм id, як в `образ_рядком`. Половина комплекту — «#N·MM/низ»."""
    н = (ном or {}).get(ід)
    т = ("#%d·%s" % н) if н else str(ід or "")
    return т + ("/%s" % частина if частина else "")


def блокери_структури(рядки, речі=None, ном=None):
    """Структурні рядки `блокує` → `[{код, речі, суть}]` за `ВЕРДИКТ_V1.структура.блокери`.

    `речі` — речі образу з `перевірити_від_моделі` ({id, слот, назва}); для
    «слот_двічі» адресою стають речі названого слота, для решти адреси нема — образ
    цілий. Вето людини (K-PC-08) сюди кладе `знахідки_вердикту`, бо його речі лежать
    у знахідці, не в рядку."""
    вих = []
    for р in (рядки or []):
        т = str(р or "")
        код = _код_блокера(т)
        if not код:
            continue
        адреси = []
        if код == "слот_двічі":
            слоти = set(_у_лапках(т))
            # ІМЕНА В ЛАПКАХ — ТЕПЕР МОЖУТЬ БУТИ СІМ'ЄЮ (рядок 47): дві пари
            # сережок у різних буквальних слотах адресуються обидві, не лише та,
            # чий літеральний слот збігся з іменем у рядку.
            адреси = [номер_речі(r.get("id"), ном, r.get("частина_комплекту"))
                      for r in (речі or [])
                      if r.get("слот") in слоти
                      or _сім_я_слота(r.get("слот"), r.get("назва")) in слоти]
        вих.append(dict(код=код, речі=адреси, суть=т))
    return вих


def _ремонт_рядком(z):
    """`ремонт` знахідки одним рядком: у `_зн` він рядок або список, у рядках
    `для_стиліста` — список `ремонти`. Схема тримає один рядок, бо модель читає
    його як пораду, а не як меню."""
    р = z.get("ремонт")
    if р in (None, "", [], ()):
        р = z.get("ремонти")
    if р in (None, "", [], ()):
        # `що_зняло_б` — ТЕЖ РЕМОНТ, і доти він до моделі не доїжджав (17.09.2026).
        # Три емітенти цього модуля пишуть саме це поле: `схема_образу` (K-PAL-03),
        # `акцент_образу` (K-PAL-18) і `палітра_образу` (K-PAL-04…15). Виміряно на
        # вердикті стенда: рядок K-PAL-14 виходив із `ремонт: null`, хоч знахідка
        # несла «той самий колір у слоті далі від обличчя». Гейт, який називає
        # межу й мовчить про вихід, — половина правила.
        р = z.get("що_зняло_б")
    if isinstance(р, str):
        return р.strip() or None
    if isinstance(р, (list, tuple)):
        ч = [str(x).strip() for x in р if str(x or "").strip()]
        if not ч:
            return None
        # `_мʼякший_ремонт` ставить першим рядком заголовок «як варіанти:»
        if ч[0].endswith(":") and len(ч) > 1:
            return ч[0] + " " + "; ".join(ч[1:])
        return "; ".join(ч)
    return None


