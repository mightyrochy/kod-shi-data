# -*- coding: utf-8 -*-
"""Прогін порівняння для Н-V34-068: єдиний критерій проти трьох історичних."""
import glob, os, re, sys
_ДЖЕРЕЛА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _ДЖЕРЕЛА)
os.chdir(_ДЖЕРЕЛА)
import прилади

# Три критерії ДО правки, дослівно з git-версії 634f658.
СТ_ПРЕФ = ("audit_", "gate_", "measure_", "check_", "build_", "стенд",
           "шаблон_", "run_", "pair_test", "підфід")
СТ_КИР = {"гейти_нові.py", "мутанти.py", "аудит_слотів.py", "траса_петлі.py",
          "звірка.py", "чистка_каталогу.py", "проба_правила.py", "скласти.py"}
СТ_ОПИС = {"status.py", "rule_genus.py"}
gate_reach_старий = lambda ф: ф[:-3].startswith(СТ_ПРЕФ) or ф in СТ_КИР or ф in СТ_ОПИС
_НЕ_СИСТЕМА = re.compile(r'^(audit_|measure_|gate_|test_|run_|build_|_)|'
                         r'^(мутанти|гейти_нові|звірка|зведення|правила|відбиток|'
                         r'проба_правила|аудит_слотів|траса_петлі|чистка_каталогу|'
                         r'скласти|підфід|rule_genus|корпус|status)\.py$')
відбиток_старий = lambda ф: bool(_НЕ_СИСТЕМА.search(ф))
АС_ПРЕФ = СТ_ПРЕФ
АС_ІМ = {"гейти_нові", "мутанти", "аудит_слотів", "траса_петлі",
         "звірка", "чистка_каталогу", "проба_правила", "скласти"}
audit_contracts_старий = lambda ф: (ф[:-3].startswith(АС_ПРЕФ) or ф[:-3] in АС_ІМ
                                    or ф[:-3] == "audit_contracts")

файли = sorted(os.path.basename(f) for f in glob.glob("*.py"))
# `прилади.py` і `склад.py` створені цією сесією — у старих критеріях їх не було;
# у новому вони ПРИЛАДИ (докстрінги цитують ID правил), тому з порівняння зняті.
старі_файли = [ф for ф in файли if ф not in ("прилади.py", "склад.py")]
новий = {ф for ф in старі_файли if прилади.прилад(ф)}
три = {"gate_reach": {ф for ф in старі_файли if gate_reach_старий(ф)},
       "відбиток": {ф for ф in старі_файли if відбиток_старий(ф)},
       "audit_contracts": {ф for ф in старі_файли if audit_contracts_старий(ф)}}
print("файлів .py (без двох нових): %d" % len(старі_файли))
print("єдиний критерій `прилади.прилад`: %d" % len(новий))
for імя, м in три.items():
    print("  %-16s старий: %2d · новий ⊇ старий: %s · новий додає: %s"
          % (імя, len(м), новий >= м, ", ".join(sorted(новий - м)) or "—"))
об = set().union(*три.values())
print("об'єднання трьох старих: %d · дорівнює новому: %s" % (len(об), об == новий))
print("нові файли сесії, оголошені приладами: %s"
      % ", ".join(ф for ф in ("прилади.py", "склад.py") if прилади.прилад(ф)))
