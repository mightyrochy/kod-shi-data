def ознаки(об):
    """Три ВИМІРЯНІ ознаки форми, з яких виводяться всі п'ять літер.

    ЯКОРІ ВИБРАНІ НЕ ДОВІЛЬНО, і перша спроба тут теж була хибна. Вона брала «низ» як
    ширину на НАЙНИЖЧОМУ одягненому рівні — тобто на щиколотці. Для скіні це 7 см проти
    36 см плечей, і образ «футболка + джинси» отримував виражену літеру V, якою його не
    назве жоден стиліст: дві ноги око читає як колону, а не як вістря трикутника.
    Тому нижній якір — НАЙШИРША точка нижче талії (стегно для більшості низів, поділ
    для розкльошених). Це те, що й формує нижню половину виду.

      нахил    = (низ − верх) / середня — розширення донизу (A) чи звуження (V);
      талія    = (min(верх, стегна) − талія) / середня — глибина втягнення (X);
      середина = (макс. у смузі груди–високе_стегно − max(верх, низ)) / середня — O.
    """
    одягнені = [з for з in об if з["одягнено"]]
    if len(одягнені) < 3: return None
    сер = sum(з["ширина"] for з in одягнені) / len(одягнені)
    if сер <= 0: return None
    i_талія = _ПОРЯДОК.index("талія")
    верхні = [з for з in одягнені if з["рівень"] in ("плечі", "груди")]
    нижні = [з for з in одягнені if _ПОРЯДОК.index(з["рівень"]) > i_талія]
    if not (верхні and нижні): return None
    верх_з = max(верхні, key=lambda з: з["ширина"])
    верх = верх_з["ширина"]
    низ_з = max(нижні, key=lambda з: з["ширина"])
    низ = низ_з["ширина"]
    талія_ш = _на(об, "талія"); стегна_ш = _на(об, "стегна")
    смуга_з = [з for з in об
               if з["рівень"] in ("груди", "талія", "високе_стегно") and з["одягнено"]]
    смуга = [з["ширина"] for з in смуга_з]
    рів = {з["рівень"]: з for з in об}
    # похибка кожної ознаки — з похибок ширин тих рівнів, з яких її складено (None — невідомо)
    похибки = dict(
        нахил=_похибка_ознаки(верх_з, низ_з, сер=сер),
        талія=(_похибка_ознаки(*[рів[к] for к in ("талія", "стегна") if к in рів], верх_з, сер=сер)
               if (талія_ш and стегна_ш) else 0.0),
        середина=(_похибка_ознаки(*смуга_з, верх_з, низ_з, сер=сер) if смуга else 0.0))
    return dict(похибки=похибки,
        нахил=round((низ - верх) / сер, 4),
        талія=round(((min(верх, стегна_ш) - талія_ш) / сер)
                    if (талія_ш and стегна_ш) else 0.0, 4),
        середина=round(((max(смуга) - max(верх, низ)) / сер) if смуга else 0.0, 4),
        середня_ширина=round(сер, 2), верх=round(верх, 2), низ=round(низ, 2),
        низ_на=низ_з["рівень"])


# ── ЛІТЕРА ЛИШЕ ПОНАД ПОХИБКУ ШИРИН (корінь Е3-одна-величина, п.6; рішення менеджера 06.11) ──
# Ознаки форми — різниці ширин обгортки на різних рівнях: ширини виробів (крій-шаблон × ширина тіла
# чи обхват виробу через π) і тіла (обхват через π). Літеру — категорію тих різниць — код називає
# лише понад похибку обох боків; інакше компонента літери «невідомо», а оцінки й ознаки йдуть фактом.
def похибка_ширини(з):
    """Похибка ширини обгортки на рівні `з`, см, чи None — невідомо.

    Ширина тіла — обхват через π: оцінка фронтальної ширини, іншої величини, ніж виміряний обхват
    (рішення 06.11 «факт замість межі», п.3), тож похибка обхвату тіла (`силует_припуск.
    похибка_обхвату_тіла`) її не дає; ширина виробу — крій-шаблон (`силует_крої.КРОЇ`, без джерела
    похибки) чи обхват виробу через π, з тією самою вадою. Джерела похибки фронтальної ширини код не
    має — «невідомо» на кожному рівні. Точка, куди стане таке джерело, — тут."""
    return None


def _похибка_ознаки(*рівні_обгортки, сер):
    """Похибка ознаки — різниці ширин двох рівнів, поділеної на середню ширину; None — невідомо."""
    е = [похибка_ширини(з) for з in рівні_обгортки]
    if None in е or not сер:
        return None
    return sum(е) / сер


def рампа(x, повна):
    """Лінійна рампа 0–1: частка `x` від `повна`, обрізана в [0, 1]; без `повна` — 0."""
    return max(0.0, min(1.0, x / повна)) if повна else 0.0


def колона(оцінки):
    """Неперервна міра «колона» H ∈ [0,1] — з тих самих оцінок, якими названо літеру.

    ЧОМУ ЦЕ ПОТРІБНО. `ЦІЛЬ_ЛІТЕРИ` називає ціллю «H» (тіло H і H/X межа) та «I»
    (тіло O), а `оцінки` їх не мала: у ній стояли лише A, V, X, O. Отже
    `гіперграф.влучання`, який бере max по ОЦІНКАХ цільових літер, для цілі «H»
    діставав 0.0 ЗАВЖДИ — половина цілі найпоширенішої фігури була недосяжна за
    побудовою, а не за виміром.

    ОДНЕ ВИЗНАЧЕННЯ (корінь Е3-одна-величина, 06.11). Доти H рахувалась окремою рампою
    розкиду трьох якорів до `розкид_колони` 0.30 («Число МОЄ, не калібровано»), тобто
    «колону» визначали двічі: літера звалась H, коли жодна з A, V, X, O не сягала 0.5, а
    оцінка H — своїм числом сесії. Тепер H — доповнення тих самих оцінок: `1 − max(A, V,
    X, O)`, і H ≥ 0.5 рівно тоді, коли літера — H. Нового числа не заводиться.

    I (вузька колона по тілу) — НЕ ОЦІНЮЄТЬСЯ: вузькість судила рампа припуску від
    `cling_межа` до `skim_стеля` 1.18 («МОЯ оцінка»; джерела дають смуги в абсолютних
    дюймах, не в відношенні, тема-1 §10.3), тож код її не знає й пише `None`. Ціль тіла O —
    («H», «I»), а I ⊆ H (вузька колона — та сама колона), тож max по цілі — H: влучання
    від невідомої I не змінюється."""
    return round(1.0 - max(оцінки["A"], оцінки["V"], оцінки["X"], оцінки["O"]), 3), None


def літера(об):
    """Літера силуету на ДВОХ ортогональних осях, а не одна з п'яти.

    ЧОМУ НЕ ОДНА. Перша версія рахувала п'ять оцінок і звала «конфліктом» малий розрив
    між першою і другою. На прогоні вона оголосила конфліктом приталений верх +
    A-line спідницю — тобто fit&flare, канонічно ВДАЛИЙ образ, у якого X і A обидві
    1.00. Правило, що спрацьовує на взірцевому образі, ловить не провал, а свою власну
    метрику. Причина: A/V/H і X/O лежать на РІЗНИХ осях. A — куди йде контур; X — чи є
    талія. «X-A» (втягнута талія + розширення донизу) — одна форма, а не дві.

      вісь тренду:   A (розширюється донизу) / V (звужується) / H (ні те, ні те)
      вісь середини: X (талія втягнута) / O (середина ширша за кінці) / — (жодного)
    """
    нд = list((об[0].get("без_довжини") if об else None) or ())
    зн = ознаки(об)
    if зн is None:
        # «БЕЗ ВХОДУ» НАЗИВАЄ ПОЛЕ, А НЕ ЛИШЕ НАСЛІДОК.
        # Обидві причини дають те саме `доступно=False`, і доти вони були
        # нерозрізненні: «речі є, але вкривають менше трьох рівнів» — це вимір,
        # а «довжини не несе жодна річ» — брак даних, який називається так само,
        # як його називає K-FIT-03: «довжина речі невідома».
        одягнених = sum(1 for з in об if з.get("одягнено"))
        return dict(доступно=False, без_довжини=нд,
                    чому=("довжина речі невідома (`верх_см`/`низ_см`) у %s — "
                          "обгортку нема з чого зібрати" % ", ".join(нд)
                          if нд and not одягнених else
                          "менше трьох одягнених рівнів — форми нема"
                          + ("; довжина невідома: %s" % ", ".join(нд) if нд else "")))
    A = рампа(зн["нахил"], C["нахил_повний"])
    V = рампа(-зн["нахил"], C["нахил_повний"])
    X = рампа(зн["талія"], C["талія_повна"])
    Oc = рампа(зн["середина"], C["середина_повна"])
    # Компоненту літери названо, лише коли ознака ± її похибка лежить по один бік межі (оцінка 0.5,
    # тобто половина `*_повний`); інакше — усі компоненти, яких вимір не розрізняє (Е3-одна-величина, п.6).
    п = зн["похибки"]
    т_A = 0.5 * C["нахил_повний"]
    тренди = tuple(("V", "H", "A")[і] for і in _категорії(зн["нахил"], п["нахил"], (-т_A, т_A)))
    є_X = _категорії(зн["талія"], п["талія"], (0.5 * C["талія_повна"],))
    є_O = _категорії(зн["середина"], п["середина"], (0.5 * C["середина_повна"],))
    середини = ("X",) * (1 in є_X) + tuple(("—", "O")[і] for і in є_O) * (0 in є_X)
    тренд = тренди[0] if len(тренди) == 1 else None
    середина = середини[0] if len(середини) == 1 else None
    назва = (None if тренд is None or середина is None else
             тренд if середина == "—" else
             (середина if тренд == "H" else f"{середина}-{тренд}"))
    Hc, I = колона(dict(A=A, V=V, X=X, O=Oc))
    # Літера порахована по РЕШТІ речей, і те, чого в ній нема, їде поруч із нею:
    # `без_довжини` порожній — контур зібрано з усього одягу образу.
    return dict(доступно=True, літера=назва, тренд=тренд, середина=середина,
                # `літера` None — компоненти не розрізнено понад похибку ширин: які можливі
                можливі=dict(тренд=тренди, середина=середини),
                чому_невідомо=(None if назва is not None else
                               "літеру образу код не називає: ширини обгортки — обхвати через π і "
                               "крій-шаблони без похибки, тож вимір не розрізняє %s / %s (оцінки — фактом)"
                               % ("/".join(тренди), "/".join(середини))),
                без_довжини=нд,
                # H та I — не мітки, а ОЦІНКИ, як A/V/X/O: `ЦІЛЬ_ЛІТЕРИ` називає їх
                # цілями (H для тіла H і H/X межі, I для O), а `гіперграф.влучання`
                # бере max саме по цьому словнику. Без них ціль «H» давала 0.0 на
                # кожній комбінації — недосяжність за побудовою, не за виміром.
                оцінки=dict(A=round(A, 3), V=round(V, 3), X=round(X, 3), O=round(Oc, 3),
                            H=Hc, I=I),
                ознаки=зн)


def відльоти(об):
    """K-SIL-01, ВИМІР. Контур образу нижче плечей — ширина обгортки поруч із шириною тіла
    на кожному одягненому рівні. Скільки окремих ВІДЛЬОТІВ у ньому читається, код НЕ лічить.

    ЧОМУ БЕЗ ЛІЧБИ (корінь Е3-одна-величина, п.2, вид межі 1; 06.11). Відліт рахувався
    окремим, коли контур від локального мінімуму йшов назовні щонайменше на
    `виразність_відльоту` 0.10 середньої ширини тіла — «моя оцінка» сесії без джерела. Межа
    «скільки має вийти контур, щоб око читало другу форму» — судження стилю; пошук 06.11
    (база знань, тема-1 §10 — пояси припуску Threads #221 в абсолютних дюймах; конструювання
    одягу, стандарти розмірів, сприйняття силуету) порогу виразності відльоту не дав. Поріг
    «> 0» замість нього теж не межа: похибку обгортки (дефолтні припуски кроїв, без повторів)
    код не рахує. Тож функція віддає лише виміряне, а читає контур стилістка
    («Код має знати те що може точно порахувати», власник 01.10).

    Що лишилось із попередніх версій як вимір, а не як суд: ширина — абсолютна (не припуск-
    відношення: широка штанина зі сталою шириною), а поруч — ширина ТІЛА того ж рівня
    (відхід контуру від тіла робить одяг, а не таз)."""
    i_пл = _ПОРЯДОК.index("плечі")
    ряд = [з for з in об if з["одягнено"] and _ПОРЯДОК.index(з["рівень"]) >= i_пл]
    if not ряд:
        return dict(контур=[], масштаб_тіла=None, середня_ширина=None)
    return dict(контур=[dict(рівень=з["рівень"], см=з["см"], ширина=round(з["ширина"], 1),
                             ширина_тіла=round(з["ширина_тіла"], 1), носій=з["носій"]) for з in ряд],
                масштаб_тіла=round(sum(з["ширина_тіла"] for з in ряд) / len(ряд), 2),
                середня_ширина=round(sum(з["ширина"] for з in ряд) / len(ряд), 2))


