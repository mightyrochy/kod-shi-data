# -*- coding: utf-8 -*-
"""ВИМІР: чи цільова функція координації МІНЯЄ РАНГ, чи підʼєднана формально.

ЧОМУ ЦЕЙ ФАЙЛ ІСНУЄ І ЧОМУ ВІН НЕ ДОКУМЕНТ. Умова прийняття задачі сформульована
як число, а не як твердження: «скільки комбінацій з пулу міняють ранг, коли
координація увімкнена. Якщо ранг не змінився — правило підʼєднане формально і
лишається мертвим». Без цього прогону «я підʼєднав K-COMP-01» — це покриття, яке
видає себе за якість (правило 1 проєкту).

ЩО МІРЯЄТЬСЯ. Один пул комбінацій, два ключі сортування:
  БЕЗ — (блокує, сума_сил, середня_відстань)          ← як було до цієї сесії
  З   — (блокує, сума_сил + вага·відхилення, ...)     ← як стало
і рахується, скільки позицій розійшлось, і чи розійшлась ПЕРША — бо саме перша
йде людині.

ЧОГО ЦЕЙ ФАЙЛ НЕ ДОВОДИТЬ. Що новий порядок ПРАВИЛЬНИЙ. Він доводить лише, що
порядок ІНШИЙ. Правильність знімається вердиктом «носитиму / ні», якого нема.
Каталог синтетичний (діалект Rozetka, `run_outfit.МОДЕЛІ`).
"""
import os, sys, tempfile
import colorspace as cs, feed, outfit as O, fit as ПС
import composer as КМ, coordination as КО, run_outfit as ПО


def _каталог():
    шлях = os.path.join(tempfile.gettempdir(), "каталог_вимір.xml")
    open(шлях, "w", encoding="utf-8").write(ПО._зібрати_xml())
    offers, _ = feed.читати_yml(шлях)
    речі = []
    for o in offers:
        арт = o.get("group_id") or o.get("id")
        hexx = ПО._HEX.get(арт)
        if not hexx:
            continue
        кат = str(o.get("категорія") or "")
        слот = ("верх" if "Блуз" in кат else "низ" if ("Спідниц" in кат or "Штани" in кат)
                else "сукня" if "Сукн" in кат else
                "взуття" if ("Туфл" in кат or "Черевик" in кат) else None)
        if not слот:
            continue
        речі.append(dict(id=o.get("id"), group_id=арт, назва=o.get("назва") or арт,
                         слот=слот, hex=hexx, lab=cs.hx(hexx),
                         ціна=o.get("ціна"), available=True,
                         тип=(o.get("категорія") or "").split("/")[-1].strip()))
    return речі


def прогін():
    F = cs.features(cs.hx("#e0bfa4"), cs.hx("#4a3528"), cs.hx("#6b7f8f"))
    тіло = ПС.тіло(167, {"плечі": 98, "груди": 90, "талія": 72, "стегна": 100,
                         "коліно": 37, "литка": 35, "зап'ястя": 15.5})
    речі = _каталог()
    print("=" * 78)
    print("ВИМІР РОЗРІЗНЮВАЛЬНОЇ ЗДАТНОСТІ ЦІЛЬОВОЇ ФУНКЦІЇ КООРДИНАЦІЇ")
    print("=" * 78)
    print("каталог: %d SKU, моделей %d" % (len(речі), len({r["group_id"] for r in речі})))

    # ВІКНА НЕ ПЕРЕДАЮТЬСЯ НАВМИСНО. Композитор тоді йде фолбек-гілкою «різні
    # моделі без колірного критерію» — і це саме той пул, на якому питання має
    # сенс: якщо колірного критерію в ВІДБОРІ нема, то весь колірний внесок у
    # РАНГ дає рівно координація, і його видно чисто.
    вих = КМ.зібрати(F, речі, вікна=None, тіло=тіло, вимір=200)
    if not вих.get("зібрано"):
        print("НЕ ЗІБРАЛОСЬ: %s" % вих.get("чому"))
        return 1
    к = вих["координація"]
    print("\nПУЛ")
    print("  комбінацій перебрано:        %d" % вих["перебрано"])
    print("  кандидатів на слот:          %s" % вих["кандидатів"])
    print("  розкид пулу:                 %s" % к["діагноз_пулу"]["чому"][:70])
    print("\nРАНГ")
    print("  вага координації в ключі:    %.2f (стеля Gray 0.44)" % к["вага"])
    print("  комбінацій змінили ранг:     %d із %d"
          % (к["комбінацій_змінили_ранг"], вих["перебрано"]))
    print("  перша (та, що йде людині):   %s"
          % ("ЗМІНИЛАСЬ" if к["вершина_змінилась"] else "та сама"))
    print("  вердикт:                     %s" % к["чи_розрізняє"])
    print("\nОБРАЗ: ЩО ЗМІНИЛОСЬ У РІШЕННІ")
    print("  ⚠ РЕЖИМ: вікна НЕ передані, отже `відстань_до_центру` = None для всіх,")
    print("    і старий третій ключ сортування тут вироджений. Тобто `before` нижче")
    print("    впорядковано сумою сил і порядком каталогу. Це НЕ применшує зсув —")
    print("    навпаки, показує, що без координації колір у ранзі не важив нічого.")
    print("    Той самий вимір на шляху З вікнами — у `run_outfit.py`, крок 6.")
    print("  before (сума_сил, далі порядок каталогу):")
    for n in (к.get("образ_без_координації") or []):
        print("     %s" % n[:56])
    print("  after  (+ ранг координації, вага %.2f):" % к["вага"])
    for r in вих["образ"]:
        print("     %s" % ((r["назва"] or "")[:56]))
    зн = [z for z in вих["знахідки"] if z.get("правило", "").startswith("K-COMP")]
    print("\nЗНАХІДКИ КООРДИНАЦІЇ НА ОБРАНОМУ ОБРАЗІ (%d)" % len(зн))
    for z in зн:
        print("  %-10s %-8s нп=%s  %s"
              % (z["правило"], z.get("сила"), z.get("сила_нп"), str(z.get("суть"))[:52]))
    if not зн:
        print("  жодної — координація втрималась або не мала входу")

    # ── ДРУГИЙ ЗРІЗ: ЧИ ЛОВИТЬ K-COMP-04 ТЕ, ЩО МУСИТЬ ────────────────────────
    print("\n" + "-" * 78)
    print("K-COMP-04 НА ОПРАЦЬОВАНОМУ ПРИКЛАДІ КОРПУСУ (тема-4 PART IV)")
    def _E(*hx):
        return O.елементи([dict(id=n, слот=s, hex=h, площа=0.33, near=0.5)
                           for n, s, h in zip(("A", "B", "C"),
                                              ("верх", "низ", "взуття"), hx)])
    для = [("приглушена шавлія + приглушена іржа  (корпус: координується)",
            ("#8a9a7b", "#a86a4a", "#c2ab90"), False),
           ("приглушена шавлія + НЕОНОВА іржа     (корпус: не координується)",
            ("#8a9a7b", "#ff5a1f", "#c2ab90"), True),
           ("чорний + молочний                    (лише світлота, не хрома)",
            ("#22222a", "#efe6d8", "#c2ab90"), False)]
    впало = 0
    for назва, hx, має in для:
        з = КО.інтенсивність(_E(*hx))
        сила = з[0]["сила_нп"] if з else 0.0
        заговорило = сила >= 0.30
        ок = (заговорило == має)
        впало += (not ок)
        print("  %s %-54s нп=%.2f" % ("✓" if ок else "✗", назва, сила))
    print("\n  третій кейс — це перевірка на семантичного двійника (Gate D):")
    print("  чисто світлотний контраст МУСИТЬ мовчати, бо він уже має власника")
    print("  в `outfit.перевірка_value`. Спрацювання тут означало б дубль.")
    print("=" * 78)
    return впало


if __name__ == "__main__":
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    raise SystemExit(прогін())
