# ── МЕРЕЖА ──────────────────────────────────────────────────────────────────
def _качати(url, реферер=None, тайм=25):
    """Байти за адресою з UA і необов'язковим Referer: три спроби на мережеву помилку.

    Адреса квотується (кирилиця й пробіли у шляхах крамниць). `HTTPError` НЕ повторюється:
    404 на великий розмір — це відповідь, а не збій, і запасний шлях у `_скачати_фото` бере
    адресу фіду одразу.
    """
    url = urllib.parse.quote(url, safe=":/?&=%#+@;,~!$*'()[]")
    заг = {"User-Agent": "Mozilla/5.0 (kod-shi zbahachennya v2)"}
    if реферер:
        заг["Referer"] = реферер
    зап = urllib.request.Request(url, headers=заг)
    for спроба in range(3):
        try:
            with urllib.request.urlopen(зап, timeout=тайм) as в:
                return в.read()
        except urllib.error.HTTPError:
            raise
        except OSError:
            if спроба == 2:
                raise
            time.sleep(2)


# ── ФОТО ────────────────────────────────────────────────────────────────────
def _відкрити(сирі):
    """Байти → PIL RGB; прозорість (RGBA/LA/P) кладеться на біле — як тло крамничного фото."""
    from PIL import Image
    im = Image.open(io.BytesIO(сирі))
    if im.mode in ("RGBA", "LA", "P"):
        im = im.convert("RGBA")
        тло = Image.new("RGB", im.size, (255, 255, 255))
        тло.paste(im, mask=im.split()[-1])
        return тло
    return im.convert("RGB")


def _b64(im, сторона=512, якість=85):
    """PIL → base64 JPEG у межах `сторона` px — стільки бачить модель."""
    к = im.copy()
    к.thumbnail((сторона, сторона))
    буф = io.BytesIO()
    к.save(буф, "JPEG", quality=якість)
    return base64.b64encode(буф.getvalue()).decode("ascii")


def _майже_біле(im):
    """Заглушка-логотип на білому: майже всі пікселі світлі й безбарвні."""
    import cv2, numpy as np
    a = np.asarray(im.resize((64, 64)))[:, :, ::-1]
    lab = cv2.cvtColor(a, cv2.COLOR_BGR2LAB).astype("float32")
    L = lab[:, :, 0] * 100.0 / 255.0
    Ch = np.hypot(lab[:, :, 1] - 128.0, lab[:, :, 2] - 128.0)
    return float(((L > 92) & (Ch < 6)).mean()) > 0.97


def аркуш(картинки, плитка=400):
    """Контактний аркуш 2×3 з номером у кутку кожної плитки.

    Номер малюється великим і на чорному полі: на пробі дрібний номер (шрифт PIL
    за замовчуванням, 11 px) модель читала як частину товару.
    """
    from PIL import Image, ImageDraw, ImageFont
    сітка = Image.new("RGB", (3 * плитка, 2 * плитка), (245, 245, 245))
    d = ImageDraw.Draw(сітка)
    try:
        шрифт = ImageFont.truetype("arial.ttf", 34)
    except OSError:
        шрифт = ImageFont.load_default()
    for i, im in enumerate(картинки[:6]):
        м = im.copy()
        м.thumbnail((плитка - 10, плитка - 10))
        x, y = (i % 3) * плитка, (i // 3) * плитка
        сітка.paste(м, (x + (плитка - м.width) // 2, y + (плитка - м.height) // 2))
        d.rectangle([x, y, x + плитка - 1, y + плитка - 1], outline=(150, 150, 150))
        d.rectangle([x + 2, y + 2, x + 46, y + 46], fill=(0, 0, 0))
        d.text((x + 15, y + 6), str(i + 1), fill=(255, 255, 255), font=шрифт)
    return сітка


