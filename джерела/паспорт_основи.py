def читач_вето(група, слово):
    """Ім'я читача цього слова вето, або None — «код цього слова не читає».

    Рядок над картками стверджує «Твої межі враховано», тож він мусить знати, чи
    код узагалі має чим це слово прочитати. Кольори мають двох читачів: клас —
    вимір речі (`колір_річ.річ_у_класі`), назва — підрядок по `колір_назва`
    (слово лексикону). Слово кольору, яке не клас і не лексикон («мокрий асфальт»,
    «щось спокійне»), не читає НІХТО: підрядковий пошук шукав би його основу в
    тексті речі, а її там не буває.
    Решта осей іде як доти: тип, тканина й принт уже стоять словами, якими їх
    називає сам запис речі."""
    w = str(слово or "").strip().lower()
    if not w:
        return None
    if група == "принти":
        # загальне «без принта» читає поле фіду `візерунок` (`profile.візерунок_збіг`, МЕЖІ-1)
        if (_ВМ.код("pattern", w) or w) == "print_generic":
            return "візерунок речі"
    if група != "кольори":
        return "слово в тексті речі"
    if _КР.клас_кольору(w):
        return "вимір кольору речі"
    return "назва кольору" if (w in _В.ЛЕКСИКОН or _В.назва_кольору(w)) else None


def вето_словами(п):
    """Тверде вето ПЛОСКИМ списком слів, у сталому порядку ключів.

    ОДИН ЧИТАЧ НА ВСІХ: той самий перелік потрібен рядку «Не хоче: …» каналу вимог
    (`пакет_моделі.рядки_переказу_полів`) і полю `межі` входу, яке читають опис і вибір
    (`міст_вхід.застосувати_паспорт`). Поки він рахувався у двох місцях, полагодити одне
    означало б лишити друге казати інше про ті самі її межі.
    """
    тв, сир = вето_чинне(п or {}), (п or {}).get("вето") or {}
    return [w for k in ("типи", "тканини", "принти", "кольори", "зони")
            for w in (сир.get(k) or [])
            if str(w).strip().lower() in {str(x).strip().lower() for x in (тв.get(k) or [])}]


def вето_чинне(п):
    """Чинні межі паспорта — готові, якщо їх уже пораховано, інакше тут-таки.

    ОДИН ЧИТАЧ НА ВСІХ. Читачів у цього переліку шестеро — шов
    (`жорстке_ні` і бриф), рядок випадку для жінки, «Твої межі враховано» на
    екрані, відсічення пулу, добори слотів і пошук за її бажанням. Поки кожен
    брав своє, гейт стояв на трьох, а пул різав сире вето моделі далі: екран
    казав «без: темні кольори», а з добору зникали куртка з жакетом, яких вона
    просила (вимір куратора на стенді, сіди 3 і 7). Збережений сценарій без
    поля меж не втрачає: тоді вони рахуються тут-таки (`вето_тверде`) з того,
    що вже лежить у паспорті, — її слів код не перечитує (Ч-4)."""
    т = (п or {}).get("вето_тверде")
    return т if isinstance(т, dict) else вето_тверде(п)


def вето_тверде(п):
    """Те з `вето` паспорта, що код СПРАВДІ тримає межею — одне обчислення на всіх.

    ЧИТАЧІВ ЦЬОГО ПЕРЕЛІКУ ШЕСТЕРО: шов (`жорстке_ні` і бриф), рядок випадку для
    жінки й для моделей, «Твої межі враховано» на екрані, відсічення пулу, добори слотів і
    пошук за її бажанням. Поки кожен брав своє, екран казав одне, а пул різав інше.

    ЩО ТРИМАЄТЬСЯ (Ч-4 — код її слів не читає, аудит/ПРОДУКТ.md п.12):
      · паспорт із мовного шару (`перекладено_шаром`) — усі межі, які почув перекладач: кожна
        вже стоїть на дослівному уривку її слів (`мовний_шар._тримається`), а слот межі
        кольору перекладач дав кодом, і `паспорт_з_шару` кладе його в `слоти`;
      · без моделі шару (виклик 0 моделі продукту) тип, тканина й принт, які назвала модель,
        — «невідомо» (`НЕВІДОМІ_БЕЗ_ШАРУ`): доти їх підтверджував словник заперечень у її
        словах, а читати її слова код більше не має чим. Зона — лише та, що вона поставила
        рукою (`зони_чипами`); старий паспорт без цього поля — як доти, без гейта. Кольори —
        як доти (гейта на них не було й тоді), на весь образ: слота без шару код не знає.
    Почуте, але не тримане, видно на картці сценарію, і там же дотик знімає почуте не те.

    ДВА СЛУЖБОВІ КЛЮЧІ — про ТІ САМІ слова, що вже в списках:
      `слоти` — про що саме сказана межа кольору (порожньо = про весь образ);
      `без_читача` — слова, які код не має чим прочитати в речі (`читач_вето`): вони лишаються
      у своєму списку (бриф везе їх стилістці), але «Твої межі враховано» їх не називає.

    Порожній паспорт або паспорт без `вето` віддає порожні списки, а не падає: цю функцію кличе
    і шов, і рядок випадку, і показ."""
    п = п or {}
    в = п.get("вето") or {}
    шар = bool(п.get("перекладено_шаром"))
    вих = {к: [w for w in (в.get(к) or []) if str(w).strip()]
           for к in ("типи", "тканини", "принти", "кольори", "зони")}
    if not шар:
        for к in НЕВІДОМІ_БЕЗ_ШАРУ:
            вих[к] = []
        _чипи = п.get("зони_чипами")
        if isinstance(_чипи, (list, tuple)):
            _чип = {str(z).strip().lower() for z in _чипи}
            вих["зони"] = [z for z in вих["зони"] if str(z).strip().lower() in _чип]
    вих["слоти"] = {}
    вих["без_читача"] = [w for к in ("типи", "тканини", "принти", "кольори")
                         for w in вих[к] if not читач_вето(к, w)]
    return вих


