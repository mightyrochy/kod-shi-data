def слова_вето(слово):
    """Слово вето людини → основи для `profile.жорстке_ні_фільтр`: саме слово плюс
    основи його класу, коли клас у режимі «вето». Незнайоме слово — як є."""
    к = str(слово or "").strip().lower()
    if not к:
        return []
    з = ВЕТО_СЛОВА.get(к)
    return [к] + ([w for w in з["слова"] if w != к] if з and з["режим"] == "вето" else [])


