# ── ЗАМОВЧУВАННЯ ФОРМИ — НЕ ЇЇ СЛОВО (розбір 1/8, В-2 і В-3, 26.09.2026) ──────
# ЩО ВИДНО. Форма сценарію несе ВШИТІ числа (`показ.ТИПОВІ_ПОЛЯ_ВИПАДКУ`:
# `сц-година`=11, `сц-темп`=18) ще до того, як жінка сказала слово, і `зібратиВхід`
# слав їх у паспорт нарівні з обраним. На проході 25.09 жінка написала рівно
# «робочий день в офісі, дрес-код business casual, без підборів» — а рядок випадку
# всіх чотирьох промптів казав «…11:00, 18 °C», картка чорним «Коли й погода —
# 11:00, +18 °C», і промпт виклику 0 подавав ці числа під рядком «що вона обрала
# плитками». Ціна не косметична: на прогулянці просто неба ці +18 °C вирішують
# верхній шар (`outer`), і стилістка казала «за такої температури верхній шар буде
# зайвим» про погоду, якої жінка не називала.
# ДРУГА ПОЛОВИНА ТІЄЇ САМОЇ ВАДИ (В-3): `поля_рукою` звало «рукою» будь-яке
# поле-плитку, що не збігається з паспортом, — отже й неторкані 11:00 і 18 °C. Її
# «ввечері о сьомій, надворі +6» лягало в паспорт, а цикл «рука» нижче затирав його
# назад на 11 і 18, і `не_взято_кодом` про це не казав нічого.
# ЩО ТЕПЕР (п.9 — нічого не замикається). Показ називає поля, яких рука не торкалась
# (`сценарій.типові_поля`), і код ставить їм цю мітку в `джерело_полів`:
#   · значення ЛИШАЄТЬСЯ в паспорті й у правилах — образи збираються, як доти, і
#     плитка на екрані стоїть із тим самим числом;
#   · але воно НЕ ЇДЕ фактом її дня: ні в рядок випадку (промпти рук 1–4 і шапка над
#     картками), ні полем випадку в пакет, ні «обраним» у промпт виклику 0 — там воно
#     стоїть окремо, з позначкою «вона цього не називала»;
#   · рука його не перебиває (`поля_рукою`), бо рука до нього не торкалась;
#   · і для поради читається як «нема» — тож стилістка м'яко питає про погоду сама.
# МІТКА — ІДЕНТИФІКАТОР, А НЕ ФРАЗА (аудит/ПРОДУКТ.md п.12): того самого роду, що «рука» й
# «розмова» поруч у `джерело_полів`. Словами це переказує мовна модель, не код.
ТИПОВЕ_ПОЛЕ_ФОРМИ = "типове_форми"


def типові_поля_форми(сценарій):
    """Поля-плитки, які показ назвав НЕТОРКАНИМИ: у формі стоїть вшите замовчування."""
    названі = {str(x) for x in ((сценарій or {}).get("типові_поля") or ())}
    # Кортеж у порядку `ПОЛЯ_ПЛИТОК`, а не множина (рядок 220): читачі обходять його й пишуть
    # `джерело_полів`, і множина давала інший порядок ключів на кожному запуску — файли
    # вердиктів ДО/ПІСЛЯ не звірялись побайтово.
    return tuple(k for k in ПОЛЯ_ПЛИТОК if k in названі)


def типові_з_форми(паспорт):
    """Поля паспорта, що стоять замовчуванням форми: жінка їх не називала.

    ОДИН ЧИТАЧ МІТКИ НА ВСІХ (рядок випадку, пакет, картка, порада): інакше кожне
    місце звіряло б рядок `джерело_полів` своїми словами й розійшлось би на першій
    правці."""
    return tuple(k for k, v in ((паспорт or {}).get("джерело_полів") or {}).items()
                 if v == ТИПОВЕ_ПОЛЕ_ФОРМИ)


