# `показ.застосуватиПаспортДоЕкрана` після кожного виклику 0 переписує плитки
# станом паспорта, а будь-який дотик до плитки ставить `ВИПАДОК_ЗМІНЕНО_П` і
# змушує перезібрати паспорт. Отже «плитка ≠ паспорт досі» означає рівно одне:
# жінка торкнулась плитки ПІСЛЯ того, як склався паспорт. Опадів тут нема
# навмисно: плитка знає дощ/сніг, а паспорт так/ні — це інший дефект (рядок 13).
# `макіяж` ДОДАНО 20.09.2026 (рядок 108): плитка «Макіяж сьогодні» і паспорт несуть
# один ключ одним форматом ({«рівень», «губи»?}); паспорт переписує плитку, а дотик
# рукою після паспорта переважає — тим самим `поля_рукою`, що й для нагоди.
# `прикраси` ДОДАНО 21.09.2026 (рядок 120): до цього дня поле паспорта задавалось
# ЛИШЕ словами в розмові (`показ.html` слова «прикраси» не містив жодного разу), і
# питання «плитка чи розмова» не виникало. З появою ручного рядка воно виникає, і
# без цього ключа `паспорт_нагоди.з_показу` віддавав би перевагу паспорту ЗАВЖДИ — тобто
# дотик до плитки після розмови мовчки не діяв би. Той самий механізм, що в `макіяж`.
# `мета` ДОДАНО 01.10.2026 (ПК-1, рядок 166): картка сценарію показує мету, яку почула
# стилістка, і дотик рукою її править — той самий механізм, що в `прикраси`.
# `мета_важливо` і `мета_зони` ДОДАНО 15.10.2026 (рядок 5211): аркуш «Чого я хочу від образу» ставить обидві
