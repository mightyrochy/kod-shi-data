# ЩО ТУТ БУЛО. Ключ кеша (`_ключ_пакета`) перелічував входи РУКАМИ, а
# `_пакет_каталогу` читав їх із `d` теж руками — двома різними списками. Списки
# розійшлись: `source` (він іде в `palette.специфікація` і міняє вікна ретриву),
# `якір` (через `_пакет` у `п`) і `паспорт` (`бажання` вставляються в пул
# ПЕРШИМИ, `вето`/`ошатність` ріжуть його у `_пакет_у_бюджет`) годували пул і
# в ключі не стояли. Наслідок мовчазний і найгіршого роду: другий виклик на
# тому самому випадку з іншим `source` діставав із кеша ЧУЖИЙ пул — рівно те,
# від чого застерігав перший рядок докстрінга `_ключ_пакета`, обіцяючи «повний
# перелік».
# ЩО СТАЛО. Входи оголошені ОДИН раз, тут. Ключ — це репрезентація цього
# словника, а не другий його список; `_пакет_каталогу` бере з нього ж і `d`
# більше не читає. Тому дірка в ключі стає неможливою ЗА ПОБУДОВОЮ: те, чого
# нема у входах, функція побудови пулу фізично не бачить. Сторож у
# `прилади/розділи_гейтів.py` (AST по `_пакет_каталогу`) стереже саме цю властивість —
# наступна правка, яка знову протягне вхід повз ключ, впаде тестом, а не
# проявиться чужим пулом через місяць.
# ЦІНА НАЗВАНА. Ключ ширший — частина нинішніх попадань стає промахами, а промах
# коштує одну побудову пулу (0.6–0.9 с на `каталог_brief.xml`). Це ціна за те,
# що попадання тепер означає «ті самі входи», а не «ті самі входи з десяти».
_СЛУЖБОВІ_ПОЗА_КЛЮЧЕМ = ("intent", "сід", "слоти_дефолтні")


def _норм_для_ключа(x):
    """Значення у вигляді, де ПОРЯДОК не вигадує різниці там, де її нема.

    dict → впорядковані пари (показ шле JSON, і порядок ключів у ньому не
    гарантований: без цього два однакові входи дали б два різні ключі й зайву
    побудову пулу). Списки лишаються ВПОРЯДКОВАНИМИ: у `бажання` порядок задає
    порядок вставки речей у пул (`_пакет_у_бюджет`), тобто він вхід, а не шум.
    """
    if isinstance(x, dict):
        return tuple(sorted((str(k), _норм_для_ключа(v)) for k, v in x.items()))
    if isinstance(x, (list, tuple)):
        return tuple(_норм_для_ключа(v) for v in x)
    return x


