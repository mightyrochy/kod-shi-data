def _лічити_речі(кандидати):
    """Скільки унікальних речей у пулі — по всіх слотах і гілках."""
    s = set()
    def г(x):
        """Обхід дерева пулу: кожен `id`, що трапився, — у `s`.

        Річ, яка вже має `id`, НЕ розкривається далі: інакше вкладені поля
        (наприклад частини комплекту) дали б ту саму річ удруге, і лічба
        «унікальних речей» перестала б бути лічбою речей."""
        if isinstance(x, dict):
            if x.get("id"): s.add(x["id"])
            else:
                for v in x.values(): г(v)
        elif isinstance(x, list):
            for v in x: г(v)
    г(кандидати or {})
    return len(s)


def _цінність_пулу(пак):
    """K-PRC-01 разом із САМОЗВІТОМ, порахований на пулі ЦЬОГО прогону.

    ЧОМУ ЦЕ ТУТ, А НЕ В CLI. `accessory.ціна_за_обхват` рахує ціну, поділену на
    комбінаторний обхват, і сама ж каже, коли її вихід вироджується назад у ціну.
    Доти цю функцію не кликав НІХТО: правило існувало в коді, лишало слід у
    трасуванні — і не міняло жодного рішення над жодною реальною річчю. Третій
    рівень за міркою проєкту, мертва гілка.

    ЩО ЦЕ МІНЯЄ В РІШЕННІ. Тестувальниця й власник бачать рядком, чи на ЦЬОМУ
    каталозі «ціна за образ» узагалі відрізняє речі, чи вона тут — та сама ціна
    під іншою назвою. Без рядка вибір між двома речами за цією віссю робився б
    наосліп на будь-якому фіді, включно з тими, де вісь не визначена.

    ПРЕДИКАТ СУМІСНОСТІ — смуга когерентності 5 ≤ ΔE00 ≤ 45, та сама, на якій
    вимір 26.08 показав різницю між вродженою й невиродженою метрикою. Він
    грубший за справжній відбір композитора, і самозвіт саме для того й існує:
    коли предикат поблажливіший за відбір, метрика вироджується, і функція це
    КАЖЕ, замість мовчки віддати число.
    """
    # П.14 (СТАНДАРТ §4): тут стояв `except Exception` → `чому="TypeError: …"` —
    # рівно та форма, яку стандарт називає порушенням: виняток, згорнутий у рядок
    # `чому`. Він робив ЗЛАМАНУ вісь ціни невідрізненною від чесної відмови
    # («у пулі замало верхів і низів»), яку ця функція вміє сказати сама й
    # каже рядком нижче. Тепер поломка летить у `bridge.виклик`, а `є=False`
    # лишається тим, чим був, — назвою СТАНУ ПУЛУ.
    import accessory as _АК, colorspace as _cs
    кат = пак.get("_каталог") or []
    у_пулі = {і for пул in (пак.get("кандидати") or {}).values() for і in
              (r.get("id") for r in пул)}
    # ── ВІСЬ РАХУЄТЬСЯ ДЛЯ ВСЬОГО ПУЛУ, А НЕ ЛИШЕ ДЛЯ ВЕРХІВ І НИЗІВ ──────
    # ЩО ЦЕ МІНЯЄ (17.09.2026). Стара версія брала лише слоти «верх» і «низ» —
    # рівно ті, з яких рахується сам обхват, — і віддавала ОДИН рядок
    # самозвіту. Тобто правило, яке корпус зве «ЄДИНОЮ метрикою теми, яку
    # система обчислює краще за людину», говорило про МЕТРИКУ і не говорило
    # про жодну РІЧ. Аксесуар, куплений дорого й сумісний із трьома речами
    # пулу, від нього не діставав нічого — а саме він (K-PRC-01: «аксесуар
    # карається за ціну СЛАБШЕ, бо має найвищу частоту використання») і є
    # предметом правила.
    # ПАРТНЕРИ ЛИШАЮТЬСЯ ВЕРХ І НИЗ: обхват — це «у скількох ОБРАЗАХ річ може
    # взяти участь», а образ тримають саме вони. Для верху партнер — низ, для
    # низу — верх, для сумки, взуття й прикраси — обидва.
    речі = [c for c in кат if c.get("id") in у_пулі]
    бази = [c for c in речі if c.get("слот") in ("верх", "низ")]
    if len(бази) < 4:
        return dict(є=False, чому="у пулі замало верхів і низів, щоб вісь мала сенс")
    def _суміс(a, b):
        """Чи можуть дві речі стояти в одному образі — смуга когерентності
        5 ≤ ΔE00 ≤ 45 (чому саме вона — в докстрінгу `_цінність_пулу` вище).
        Річ без кольору не рахується сумісною ні з чим."""
        if not (a.get("lab") and b.get("lab")):
            return False
        return 5.0 <= _cs.de00(tuple(a["lab"]), tuple(b["lab"])) <= 45.0
    р = _АК.ціна_за_обхват(речі, речі, сумісні=_суміс)
    д = р["дискримінація"]
    з_ціною = [x for x in (р.get("кандидати") or []) if x.get("ціна_на_образ") is not None]
    # ── ЧИСЛО ПОВЕРТАЄТЬСЯ В РЯДОК РЕЧІ, І ЦЕ ВЕСЬ НАСЛІДОК ПРАВИЛА ───────
    # Доти вихід `ціна_за_обхват` жив рівно тут, у самозвіті, і вмирав разом
    # із ним: жодна річ не несла свого числа далі, тож ані суд, ані пояснення
    # жінці його не бачили. Тепер кожна річ пулу несе `ціна_на_образ`,
    # `обхват_у_пулі` й РАНГ усередині СВОГО слота — частку речей того самого
    # слота, які на образ коштують дешевше. Ранг, а не гривні: корпус прямо
    # забороняє подавати це число як прогноз носінь і дозволяє рівно одне —
    # порівняння двох кандидатів у ТОМУ САМОМУ пулі.
    # ВИРОДЖЕНУ ВІСЬ НЕ ЗАПИСУЄМО ЗОВСІМ: функція сама каже, коли її вихід —
    # це ціна під іншою назвою, і мовчки віддати таке число судові означало б
    # зробити рівно те, що вона забороняє.
    за_ід = {c.get("id"): c for c in речі}
    if not д.get("вироджена"):
        за_слотом = {}
        for x in (р.get("кандидати") or []):
            if x.get("ціна_на_образ") is not None:
                за_слотом.setdefault(x.get("слот"), []).append(x)
        for сл, рядки in за_слотом.items():
            рядки.sort(key=lambda x: x["ціна_на_образ"])
            n = len(рядки)
            for i, x in enumerate(рядки):
                c = за_ід.get(x.get("_ід"))
                if c is None:
                    continue
                c["ціна_на_образ"] = x["ціна_на_образ"]
                c["обхват_у_пулі"] = x["обхват"]
                c["ціна_ранг"] = round(i / max(1, n - 1), 3) if n > 1 else None
                c["ціна_ранг_з"] = n
    return dict(є=True, вироджена=bool(д.get("вироджена")), чому=д.get("чому"),
                обхват_мін=д.get("обхват_мін"), обхват_макс=д.get("обхват_макс"),
                відносний_розкид=д.get("відносний_розкид"),
                речей=len(речі), баз=len(бази), з_ціною=len(з_ціною),
                рангів=sum(1 for c in речі if c.get("ціна_ранг") is not None))


