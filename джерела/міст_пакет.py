    # речі, приблизно порівну; аксесуари лише відлунюють. Слова ті самі, що в рядку
    # жінці (`palette.слово_сім_ї`), щоб модель і картка говорили про одні кольори.
    _сім0 = ((_специфікації[0].get("сім_ї_схеми") or []) if _специфікації
             and _специфікації[0].get("поверхні") == "великі" else [])
    if _сім0:
        import palette as _P_р
        _сл0 = [_P_р.слово_сім_ї(с, п.get("вибір_кольору")) for с in _сім0]
        _рамка["правила"] = list(_рамка.get("правила") or []) + [dict(рядок=(
            "Схема «%s»: %s — %s, кожна на СВОЇЙ ВЕЛИКІЙ речі (верх, низ або сукня, другий шар — "
            "жакет чи кардиган — або верхній шар), приблизно рівними площами. Сумка, взуття й "
            "прикраси можуть повторити одну з них, але кольору схеми самі не несуть: образ, де "
            "колір лише на аксесуарах, цю схему НЕ виконує. Разом із металом прикрас — не більше "
            "трьох кольорових сімей."
            % (схема, "три кольорові сім'ї" if len(_сім0) == 3 else "дві сторони пари",
               ", ".join(_сл0))))]
    elif _акц0:
        _осн0 = (_специфікації[0].get("обрана_основа") or {}) if _специфікації else {}
        # ФОРМУЛЮВАННЯ ЙДЕ ЗА СХЕМОЮ, А НЕ ОДНЕ НА ВСІ: «один акцент» —
        # це текст саме «нейтрали+акцент» (корпус K-COL-03, п. 1). Тональній
        # чи аналоговій казати «рівно одна кольорова річ» було б неправдою:
        # там кольорових речей законно кілька, в одній дузі. Спільне в них
        # одне — образ БЕЗ ЖОДНОГО кольору не виконує жодної з них.
        _дзеркало = (" Дві й більше РІЗНИХ кольорових сімей ламають цю схему з другого "
                     "боку: акцент тут один." if схема == "нейтрали+акцент" else "")
        _рамка["правила"] = list(_рамка.get("правила") or []) + [dict(рядок=(
            "Схема «%s»: колір образу несуть слоти %s, решта лишається нейтральною. "
            "Образ, у якому ЖОДНА річ не несе кольору, цю схему НЕ виконує — це не "
            "спокій, а прісність.%s%s"
            % (схема, ", ".join(_акц0[:6]), _дзеркало,
               (" Жінка обрала основу %s — саме цей колір і має бути кольором образу, "
                "речі його сім'ї в пулі є." % _осн0.get("hex")) if _осн0.get("hex") else "")))]
    пак = (_PL.пакет_для_моделі(F, пр["каталог"], T, слоти, вікна, сцен,
                                K=int(вх["K"]), варіантів=_вар,
                                рамка=_рамка, чистити=_без_ід_глибоко,
                                розвести_з=_розвід, вже_були=вх["вже_були"]) if вх["K"]
           else _пакет_у_бюджет(_PL, F, пр["каталог"], T, слоти, вікна, сцен, _вар,
                                бюджет=вх["бюджет_символів"], паспорт=вх["паспорт"],
                                жорстке_ні=вх["жорстке_ні"], вето=вх["вето"],
                                самозвіт=вх["самозвіт"], рамка=_рамка,
                                розвести_з=_розвід,
                                # СХЕМА ЇДЕ САМА, А НЕ ДРУГИМ ПЕРЕЛІКОМ АКЦЕНТНИХ
                                # СЛОТІВ (рядок 127): ролі слотів і дуги тону живуть
                                # у специфікації, і копія їх тут розійшлася б із
                                # `palette.специфікація` на першій же правці.
                                спец=(_специфікації[0] if _специфікації else None),
                                не_ця=вх["не_ця"], вже_були=вх["вже_були"]))
    пак["_каталог"] = пр["каталог"]
    _ОСТАННІЙ_ПАКЕТ.append(_к)
    # СПЕКА СЛОТІВ ЇДЕ РАЗОМ ІЗ ПУЛОМ. Без неї суддя не має з чим звіряти
    # виконання: ролі («акцент», «домінанта») і межі хроми живуть тільки в
    # специфікації, а `перевірити_від_моделі` бачив лише речі. Саме тому
    # припис «взуття — акцент» ніхто не перевіряв.
    # РЕЖИМ «НЕ ОБИРАЛА» ТЕПЕР ЦЮ ПЕРЕВІРКУ ДІСТАЄ (Н-V05-015). Доти союз
    # чотирьох схем давав тут порожню спеку — ролі слотів у схемах різні,
    # спільного припису нема, — і K-PAL-18 мовчав саме там, де людина коду
    # довірилась найбільше. Відколи гілка підставляється (0) і називається,
    # `_специфікації` має довжину 1 сама собою, і жодного окремого правила
    # для цього режиму тут не треба. Порожня спека лишається означати «нема
    # припису», але тепер вона означає це ЛИШЕ на вході без гілок.
    # ── ПАЛІТРА ЇДЕ ДО СУДДІ РАЗОМ ЗІ СЛОТАМИ (K-PAL-07…15, 17.09.2026) ──
    # `pipeline.палітра_образу` судить образ прийомами практикової палітри, і
    # для цього йому потрібні три речі, які всі стоять РІВНО тут: сама палітра
    # (вікна, найдальші, активні прийоми), рівень контрасту особи й намір.
    # Службові ключі на «_» суддя вже вміє відрізняти від слотів
    # (`акцент_образу`), тож окремого каналу не заводиться.
    пак["_спец_слоти"] = ({} if len(_специфікації) != 1 else
                          dict(_специфікації[0].get("слоти") or {},
                               # схема великих поверхонь (рядок 133): суд вимагає її сім'ї
                               # на великих речах тим самим переліком, яким пул їх добирав
                               **({"_поверхні": "великі",
                                   "_сім_ї": _специфікації[0].get("сім_ї_схеми") or []}
                                  if _специфікації[0].get("поверхні") == "великі" else {}),
                               _схема=_специфікації[0].get("схема"),
                               _палітра=_специфікації[0].get("палітра_практична"),
                               # контраст береться З САМОЇ ПАЛІТРИ, а не з
                               # сусіднього поля: `палітра_практична` складена
                               # саме з цим рівнем, і два джерела розійшлись би
                               _контраст=((_специфікації[0].get("палітра_практична") or {})
                                          .get("контраст_рівень")),
                               _намір=вх["намір"]))
    # ЧИЙ ЦЕ ПРИПИС — ЇДЕ РАЗОМ ІЗ ПРИПИСОМ. Без цього поля знахідка
    # K-PAL-18 звучала б однаково там, де схему обрала людина, і там, де її
    # підставив код; а «ти пішла проти власної спеки» за припис, якого вона
    # не давала, — рівно та помилка атрибуції, від якої застерігає
    # `pipeline.акцент_образу`.
    пак["гілка_за_замовчуванням"] = за_замовчуванням
    # ── ВХІД K-ACC-07 ЇДЕ РАЗОМ ІЗ ПУЛОМ (07.09.2026) ────────────────────
    # K-ACC-07 — ЄДИНЕ правило теми-10, що каталог РОЗШИРЮЄ, а не звужує: коли
    # приобличчеве поле займає шарф чи оправа, верх звільняється до дальнього
    # вікна (K-COL-08), і пул верхів росте. Йому потрібні дві речі: `спец`
    # (специфікація з `палітра_практична.найдальші`) і `запити` (вікна у фід).
    # Обидві тут БУЛИ й нікуди не їхали: `pipeline` їх передає в `accessory` з
    # приміткою «без них правило кликалось лише з тестів і не міняло жодного
    # рішення», а дістати їх не було звідки. Тепер вони в пакеті.
    пак["_спец_палітри"] = _специфікації[0] if _специфікації else None
    пак["_запити_у_фід"] = [q for _сп in спец for q in (_сп or []) if isinstance(q, dict)]
    пак["пул_без_фільтра"] = _без_фільтра
    пак["прогін"] = dict(офферів=пр["офферів"], з_кольором=пр["з_кольором"], без_слота=пр["без_слота"])
    пак["каблук"] = _каблук_слід
    # ── K-PRC-01 РАХУЄТЬСЯ ТУТ, А НЕ У ВІДПОВІДІ `запити` (17.09.2026) ────
    # Доти самозвіт осі цінності будувався у відповіді ендпойнта `запити`. Поки
    # він був ЛИШЕ звітом, місце не важило; відколи він кладе `ціна_ранг` у
    # рядок речі — важить вирішально: `від_моделі` бере пакет із кеша
    # (`_пакет_каталогу` віддає збережений), і в сесії, яка починається з
    # вердикта, `запити` не викликається взагалі. Тобто правило працювало б
    # або не працювало залежно від того, з якого боку зайшли, — а це найгірший
    # рід мовчання: невідтворюваний. Тепер вісь є властивістю ПАКЕТА.
    пак["_цінність"] = _цінність_пулу(пак)
    if len(_КЕШ_ПАКЕТА) >= 2: _КЕШ_ПАКЕТА.clear()
    _КЕШ_ПАКЕТА[_к] = пак
    return _запам_ятати(пак)
