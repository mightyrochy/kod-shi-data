def _смуга(дизайн_см):
    """Опублікована смуга, у яку падає дизайн-припуск (см)."""
    for назва, лоу, хай in СМУГИ:
        if дизайн_см < лоу: continue
        if хай is None or дизайн_см < хай: return назва, лоу, хай
    return СМУГИ[-1][0], СМУГИ[-1][1], None


def операція(припуск, рівень=None, обхват_тіла=None, текстура=None, шар="базовий",
             крій=None, рід=None):
    """Що річ робить із зоною — на АБСОЛЮТНІЙ осі припуску в сантиметрах обхвату.

    ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after), і це вимір, а не переказ:
      before — мітка різалась на ВІДНОШЕННІ виріб/тіло з порогами 1.00 / 1.18 / 1.25.
               Виміряно (вимір_припуску.py на медіанних грудях 92 см): `skim` тримав
               46.0% простору припуску — тобто зливав чотири опубліковані категорії
               в одну, і за критерієм §10.4 це провал (≥45%). Межа cling→skim стояла
               рівно на 0.0 см припуску, тобто код називав «ковзанням» полотняну річ,
               скроєну по обхвату тіла, яку неможливо застібнути (§17.2). Та сама
               мітка означала різне на різних тілах: skim_стеля=1.18 давала 5.7" на
               грудях 80 і 8.5" на грудях 120 — код мовчки щедрішав із розміром.
      after  — вісь у сантиметрах, різана по опублікованих смугах Threads #221, а
               нуль осі — МІНІМУМ НОСІННЯ ЦЬОГО ЛАНДМАРКА (МІН_НОСІННЯ), не тіло.
               З'являється стан `нижче_мінімуму`: річ, яку не вдягнути, більше не
               ховається всередині «cling».

    ВХІД. `припуск` — відношення ширина_виробу/ширина_тіла (те, що дає обгортка()).
    `обхват_тіла` — обхват тіла на цьому рівні в см; без нього абсолютної осі не
    існує і функція чесно повертає ВІДНОШЕННЄВИЙ фолбек, позначений `вісь="відношення"`.
    Тема-1 §10.4 велить лишити фолбек саме так: «keeping the ratio only as a fallback
    when the size chart gives no circumference».

    УМОВИ ЗАСТОСУВАННЯ (правило 2 — коли діє, наскільки, де ламається):
      · діє на ПОЛОТНІ. У трикотажі припуск є функцією розтяжності й регулярно
        від'ємний — опубліковані мінімуми там не діють узагалі (§17.1, §17.2).
        Тому при `текстура`-трикотажі стан `нижче_мінімуму` НЕ виноситься.
      · `текстура=None` — тканина невідома. Стан виноситься, але з міткою
        `умова_невідома`, і викликач зобов'язаний зрізати силу.
      · ландмарк без опублікованого мінімуму (плечі, коліно, литка) мовчить:
        `мінімум=None`, `нижче_мінімуму` неможливий.
      · верхній шар: уся таблиця підіймається на C["зсув_шару_см"] (§10.2 —
        «the whole table shifts up ¾–2" for garments worn over other garments»).
      · ЛАМАЄТЬСЯ ТАМ САМО, ДЕ Й РАНІШЕ, і §10.5 це називає: всі джерела описують
        вікно ковзання через ТКАНИНУ (щільність, драп), а не через припуск.
        Абсолютні смуги лагодять АРИФМЕТИКУ, а не залежність від тканини. Драп у
        системі не виміряний — це лишається найімовірнішим джерелом хибних спрацювань.
    """
    if припуск is None: return None
    # РІД: спершу вимір із фіду, потім дефолт крою. Крій "обидва" рід не дає — і це
    # правильно: bodycon без текстури трикотажний за конструкцією, а skinny — ні.
    # ПРІОРИТЕТ: слово назви (факт фіду про конструкцію) > ключ текстури > дефолт крою.
    рід_джерело = "слово назви (verify.рід_зі_слова)" if рід else None
    if рід is None:
        рід = рід_тканини(текстура)
        рід_джерело = "вимір (`текстура`)" if рід else None
    if рід is None and крій:
        _р = рід_за_кроєм(крій)
        if _р in ("трикотаж", "полотно"):
            рід, рід_джерело = _р, ("дефолт крою «%s» (не вимір)" % крій)
    м = МІН_НОСІННЯ.get(рівень) if рівень else None
    мін = (м or {}).get("см")
    зсув = C["зсув_шару_см"] if шар in ("верхній", "жакет", "пальто") else 0.0

    # ── фолбек: обхвату нема, абсолютної осі не існує ────────────────────────
    if обхват_тіла is None or обхват_тіла <= 0:
        назва = ("skim" if C["cling_межа"] <= припуск <= C["skim_стеля"] else
                 "cling" if припуск < C["cling_межа"] else
                 "перехід" if припуск < C["tent_межа"] else "tent")
        поза = (0.0 if назва == "skim" else
                round(C["cling_межа"] - припуск, 3) if назва == "cling" else
                round(припуск - C["skim_стеля"], 3))
        return dict(вид=назва, смуга=None, вісь="відношення", припуск=round(припуск, 3),
                    рід_тканини=рід, рід_джерело=рід_джерело,
                    поза_вікном_см=None, поза_вікном=поза,
                    чому_фолбек="обхвату тіла на рівні не передано — опубліковані смуги "
                                "стоять в абсолютних дюймах і без обхвату не рахуються "
                                "(тема-1 §10.4)")

    повний_см = обхват_тіла * (припуск - 1.0)          # см обхвату, повний припуск
    # ── нижче мінімуму носіння ───────────────────────────────────────────────
    if мін is not None and повний_см < мін - 1e-9 and рід != "трикотаж":
        return dict(
            вид="cling", смуга="нижче_мінімуму", вісь="см", припуск=round(припуск, 3),
            повний_припуск_см=round(повний_см, 1), дизайн_припуск_см=None,
            мінімум_см=мін, мінімум_джерело=м["джерело"], мінімум_нота=м["нота"],
            поза_вікном_см=round(мін - повний_см, 1),
            поза_вікном=round(мін - повний_см, 1),
            рід_тканини=рід, рід_джерело=рід_джерело, умова_невідома=(рід is None),
            чому="повний припуск %.1f см нижче опублікованого мінімуму носіння %.1f см "
                 "на рівні «%s» — полотняну річ на цьому обхваті не вдягнути. Це не "
                 "«облягає», це не носиться (тема-1 §17.2)" % (повний_см, мін, рівень),
            неоднозначність="вісь смуг прочитана як ДИЗАЙН-припуск понад мінімум "
                            "(тема-1 §17.2); конверт Big Four друкує ПОВНИЙ припуск — "
                            "розбіжність = мінімум носіння цього ландмарка")

    # ── дизайн-припуск: те, що додано понад мінімум ──────────────────────────
    база = (мін if мін is not None else 0.0) + зсув
    дизайн = повний_см - база
    назва, лоу, хай = _смуга(max(дизайн, 0.0) if дизайн >= 0 else дизайн)
    if дизайн < 0: назва, лоу, хай = "close-fitting", 0.0, СМУГИ[0][2]

    # відстань до ВІКНА КОВЗАННЯ (fitted..semifitted), у см
    вікно_лоу = next(л for н, л, _ in СМУГИ if н == СМУГИ_КОВЗАННЯ[0])
    вікно_хай = next(х for н, _, х in СМУГИ if н == СМУГИ_КОВЗАННЯ[-1])
    поза = (0.0 if назва in СМУГИ_КОВЗАННЯ else
            round(вікно_лоу - дизайн, 1) if дизайн < вікно_лоу else
            round(дизайн - вікно_хай, 1))

    return dict(
        вид=СМУГА_У_ВИД[назва], смуга=назва, вісь="см", припуск=round(припуск, 3),
        повний_припуск_см=round(повний_см, 1), дизайн_припуск_см=round(дизайн, 1),
        мінімум_см=мін, мінімум_джерело=(м or {}).get("джерело"),
        мінімум_нота=(м or {}).get("нота"),
        зсув_шару_см=(зсув or None), поза_вікном_см=поза, поза_вікном=поза,
        рід_тканини=рід, рід_джерело=рід_джерело,
        умова_невідома=(рід is None and мін is not None),
        смуга_межі=(лоу, хай),
        чому=("повний припуск %.1f см; мінімум носіння %s → дизайн-припуск %.1f см "
              "= смуга «%s» (Threads #221). Вікно рівної лінії — %s: %.1f–%.1f см"
              % (повний_см, ("%.1f см (%s)" % (мін, (м or {}).get("джерело")))
                 if мін is not None else "не опубліковано для цього рівня",
                 дизайн, назва, "/".join(СМУГИ_КОВЗАННЯ), вікно_лоу, вікно_хай)),
        неоднозначність="вісь смуг прочитана як ДИЗАЙН-припуск понад мінімум "
                        "(тема-1 §17.2); конверт Big Four друкує ПОВНИЙ припуск — "
                        "розбіжність = мінімум носіння цього ландмарка")
