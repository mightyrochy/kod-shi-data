# ── ВІСЬ K-MAT-06 З КАНОНІЧНОГО ІМЕНІ КРОЮ (17.09.2026) ─────────────────────
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. `outfit.елементи` кладе в елемент поле `прилягання`
# (вісь K-MAT-06: cling / skim / stand-away) і бере його з САМОЇ РЕЧІ:
# `r.get("прилягання", r.get("посадка", "skim"))`. Обидва імені не пише НІХТО —
# ні `feed`, ні `composer._у_річ`, ні рука. Тобто на живому шляху поле дорівнює
# «skim» у 100 % випадків, а єдиний його споживач — K-WEA-03 («темне + пряме
# сонце + облягання») — відсіював КОЖНУ річ першим же рядком і не міг вийти
# ніколи. Клас той самий, що в K-OUT-28 (сирі українські літерали проти
# канонічного словника `КРОЇ`), тільки тут поля нема зовсім.
# ВХІД, ЯКИЙ У СИСТЕМІ Є: `крій`. Виміряно на `каталог_повний` 17.09.2026 —
# 2 213 речей із 8 975 несуть канонічне ім'я крою, з них 435 мають рід
# «прилягає» (fitted 277, wrap 97, sheath 25, peplum 25, pencil 10, skinny 1).
# ЧОМУ САМЕ `рід`, А НЕ СПИСОК ІМЕН. Рід — це те, що слово «крій» означає
# КОНСТРУКТИВНО, і таблиця КРОЇ вище визначає його дослівно: «прилягає — ширина
# виробу задана тілом», «відходить — нижче точки відльоту ширину задає САМ
# ВИРІБ». Перше і є «зазору між тканиною й шкірою нема» — умова K-WEA-03;
# друге і є «зазор 10–28 мм», яким бедуїнський халат знімає різницю.
# МЕЖА, І ВОНА НАЗВАНА: рід двозначний, а вісь K-MAT-06 тризначна. Середній
# стан («skim» — річ іде за тілом, не липнучи) і «stand-away» родом не
# розрізняються, тому «відходить» лишається старим дефолтом «skim», а не стає
# «stand-away»: стверджується лише те, що вимірюється. Тканину сюди теж не
# вплетено — K-MAT-06 називає cling через трикотаж, і з 435 приляглих кроїв
# трикотажних за `рід_за_кроєм` лише 5. Правило з силою `hint`, що спрацювало б
# п'ять разів на весь каталог, не відрізнити від вимкненого.
ПРИЛЯГАННЯ_ЗА_РОДОМ = {"прилягає": "cling", "відходить": "skim"}


def прилягання_за_кроєм(крій):
    """Вісь K-MAT-06 (cling / skim) з канонічного імені крою, або None.

    None — крою не названо або він не в `КРОЇ`: викликач лишає свій дефолт.
    Програє явному полю речі, як і `рід_за_кроєм` програє виміряній текстурі."""
    return ПРИЛЯГАННЯ_ЗА_РОДОМ.get((КРОЇ.get(крій) or {}).get("рід"))

