def мінімум_носіння(рівень):
    """(см, опубліковано?, нота) для ландмарка.

    `опубліковано` = True лише там, де число стоїть у стовпці Threads #221. Для
    перенесених (щиколотка ← зап'ястя, високе_стегно ← стегно) — False, і викликач
    зобов'язаний це показати: перенесене число не має права звучати як вимір.
    Для ландмарків без мінімуму повертає (None, False, чому)."""
    м = МІН_НОСІННЯ.get(рівень)
    if not м: return None, False, "ландмарк невідомий модулю"
    return м["см"], (м["джерело"] == "опубліковано"), м["нота"]


def рід_тканини(текстура):
    """Полотно / трикотаж / невідомо — з поля `текстура`, яке речі вже несуть."""
    if not текстура: return None
    t = str(текстура).strip().lower()
    if any(t.startswith(p) or p in t for p in _ТРИКОТАЖ_ПРЕФІКСИ): return "трикотаж"
    if t in _ПОЛОТНО_КЛЮЧІ: return "полотно"
    return None      # ключ формальності без конструкції («софт») — рід НЕ вгадується


