"""Стратифікована вибірка кандидатів під бюджет.

ЧОМУ ЦЕ ІСНУЄ. Чинна стеля бере ПЕРШІ K кожної гілки. Зміряно на каталог_повний:
верх 399→60 (−85 %), взуття 401→60 (−85 %), сумка 246→60 (−76 %), низ 169→60 (−64 %),
а на брошці (1), шкарпетках (2), сережках (7) плоскі 60 не роблять нічого. Тобто
плоский зріз одночасно надто жорсткий до багатих слотів, безкорисний на бідних —
і СПОТВОРЮЄ ПРОПОРЦІЇ: модель бачить порівну взуття й низу, хоч у каталозі їх
401 проти 169. Крім того «перші K» після стабільного сорту дає верхівку одного
впорядкування, а не переріз пропозиції: тип, магазин і цінова смуга губляться
цілими класами.

ЩО ЦЕ МІНЯЄ НАД РЕАЛЬНОЮ РІЧЧЮ. Модель дістає не «топ-60 за одним ключем», а
переріз: кожен тип речі, кожна смуга світлоти й кожна гілка присутні хоча б раз,
перш ніж будь-яка з них отримає другу річ; усередині страти магазини йдуть по колу,
а всередині магазину кожна придатна річ має рівний шанс (сід), без цінових якорів.

МЕЖІ. Підлога `ПІДЛОГА_СЛОТА` — це підлога ВИБІРКИ, не вікна. Якщо крізь колірні
вікна людини пройшло 7 сережок, семплер не зробить із них 20: він віддасть усі 7.
Дати 20 можна лише розширенням вікна (гілка «на межі»), і це інший важіль.

СТАТУС ЧИСЕЛ. `ПІДЛОГА_СЛОТА = 20` — рішення власника (31.08.2026), не калібрування:
воно про те, скільки речей робить слот вибором, а не ілюстрацією. Фольклорна
константа, T3, до перевірки вердиктами.
"""

import collections
import random

ПІДЛОГА_СЛОТА = 20


def _перемішати(послідовність, сід, мітка):
    """Той самий механізм, що в `composer._перемішати`, і з тієї ж причини.

    `сід=0` — «сіда нема»: тести й CLI дістають ту саму вибірку, що й до появи
    сіда, інакше червоне в регресії перестає означати «зламано». Рядковий сід, не
    число: `hash()` рядків рандомізується між процесами (PYTHONHASHSEED).
    """
    if not сід:
        return послідовність
    random.Random("%d|%s" % (сід, мітка)).shuffle(послідовність)
    return послідовність


def _магазин(r):
    """Магазин речі — хвіст її `id` після «@»; ним страта ділиться на групи,
    які потім віддають речі по колу (`_по_колу`)."""
    return (r.get("id") or "").split("@")[-1]


# ЦІНА ЯК ВІСЬ СТРАТИ — ПЕРЕВІРЕНО Й ВІДХИЛЕНО (31.08.2026).
# Гіпотеза: покриття ціни впало проти плоского зрізу (взуття 55 %→32 %), бо ціна
# лежить усередині страти й до неї не доходить черга. Правка: додати цінову смугу
# в ключ страти. ЗМІРЯНО — стало ГІРШЕ: страти подрібнились учетверо, обхід по колу
# дійшов лише до першої речі кожної, і впало покриття ТИПІВ (верх 14/20→10/20,
# сумка 5/5→2/5) і ЗОН (взуття 23/28→15/28), а ціна не виправилась (32 %).
# ПРАВИЛО, ЯКЕ З ЦЬОГО ВИПЛИВАЄ: осей стратифікації вже більше, ніж квота
# (верх — 20 типів × 79 зон × 28 магазинів), тож кожна ДОДАНА вісь відбирає
# покриття в решти. Осі треба впорядковувати за важливістю й покривати
# послідовно, а не множити в декартів добуток.

def _страта(r):
    """Ключ страти. Ті самі осі, що стають заголовком групи в промпті, — щоб
    структура, яка робить промпт дешевшим, і структура, яка тримає різноманіття,
    були однією структурою, а не двома, що розходяться на першій же правці."""
    return (r.get("гілка") or "ядро",
            r.get("тип") or "?",
            r.get("зона") or "?")


def _рівним_шансом(речі, сід=0):
    """Порядок речей однієї групи (страта × магазин): із сідом — перемішування, тож
    кожна придатна річ має рівний шанс стати першою; без сіда — порядок входу."""
    # ЦІНОВЕ ПРАВИЛО ПРИБРАНО (26.09.2026, рішення власника: «максимально погане
    # рішення»). ЩО БУЛО. Тут стояв `_розкидом`: сорт за ціною, першими — найдешевша,
    # найдорожча й медіанна, і ці три від сіда НЕ залежали. Коло бере з групи по одній
    # речі, а на тісній квоті до другої черга не доходить, тож група завжди віддавала
    # ту саму найдешевшу. Виміряно Д-1 (PR #355, `проби/повтор_страти.py`): сумок
    # досяжно жодним сідом 50 із 123 (41 %), браслетів 16 із 38; за 18 пулів модель
    # не бачила 83.1 % каталогу. ЩО СТАЛО: ціни семплер не читає зовсім; досяжна
    # кожна річ групи, а ціна потрапляє в пакет тим розподілом, який має каталог.
    return _перемішати(list(речі), сід, "група")


def _по_колу(групи):
    """Обхід груп по колу: кожна віддає одну річ, перш ніж будь-яка віддасть другу."""
    черги = [list(v) for v in групи if v]
    while черги:
        далі = []
        for ч in черги:
            yield ч.pop(0)
            if ч:
                далі.append(ч)
        черги = далі


def вибрати_зі_слота(речі, квота, сід=0):
    """Квота речей одного слота, розкладена по стратах.

    Спершу страти віддають по одній речі по колу (перерізу гарантовано вистачає
    на всі типи й смуги), і лише коли кожна страта представлена, більші страти
    починають наповнюватись. Усередині страти магазини йдуть по колу, а всередині
    магазину — рівним шансом (`_рівним_шансом`)."""
    # ДОЗА «НА МЕЖІ» БЕЗ НАМІРУ: композитор кладе запас удвічі (для руки 2), а модель бачить
    # рівно дозу слота — і тоді, коли слот влазить цілком (ПУЛ-НАМІР).
    _доза = [r for r in речі if isinstance(r, dict) and r.get("_доза")]
    if _доза and len(_доза) > min(int(r["_доза"]) for r in _доза):
        _лишити = {id(r) for r in _перемішати(list(_доза), сід, "доза")[:min(int(r["_доза"]) for r in _доза)]}
        речі = [r for r in речі if not (isinstance(r, dict) and r.get("_доза")) or id(r) in _лишити]
    if квота >= len(речі):
        # СЛОТ, ЯКИЙ ВЛАЗИТЬ ЦІЛКОМ (брошка 11, кольє 9 на стенді), іде ЦІЛКОМ: кожна
        # його річ і так видима моделі щоразу, а зрізати його нижче підлоги слота
        # (рішення власника 31.08) означало б ховати речі, коли бюджет є. Що в ньому
        # повторювалось — ПОРЯДОК: доти слот ішов порядком входу на кожному сіді, і
        # модель, що бере згори (Д-1, `повтор_позиція.py`: перша річ слота 12 %
        # виборів проти 3 % за рівного шансу), брала ту саму річ. Тепер порядок —
        # сідом, як і в зрізаних слотах; без сіда — порядок входу, як доти.
        return _перемішати(list(речі), сід, "цілком")
    # ── ОБРАНИЙ КОЛІР ПЕРЕЖИВАЄ ЗРІЗ (19.09.2026) ────────────────────────────
    # ТОЙ САМИЙ ЯРУС, ЩО Й ВАГА ОБОВ'ЯЗКОВОГО СЛОТА НИЖЧЕ, лише всередині слота:
    # там квота стерегла, щоб слот не зник, тут — щоб із слота не зникла ЄДИНА
    # річ того кольору, який назвала жінка. Страта семплера («тип · зона ·
    # гілка») кольору не знає за побудовою, тож на тісному бюджеті три фіалкові
    # черевики з шести законно програвали чорним: вони не рідкісна страта, вони
    # рідкісний КОЛІР. Виміряно 19.09 на каталог_повний (основа поза ядром
    # асортименту): у пулі 4 речі обраної сім'ї, у пакеті — 1.
    # ПОЛЕ СТАВИТЬ ТОЙ, ХТО ЗНАЄ ПРО ВИБІР (`bridge._пакет_у_бюджет`), а не
    # семплер: колір — це палітра, а тут модуль-лист, який нічого проєктного не
    # імпортує. Де прапорця нема, зріз лишається побайтово тим самим.
    # СУМА НЕ РОСТЕ: утримані входять У квоту, а не понад неї.
    тримані, решта_речей = [], []
    for r in речі:
        (тримані if (isinstance(r, dict) and r.get(ПОЛЕ_УТРИМАННЯ)
                     and len(тримані) < min(МІН_ОБОВЯЗКОВОГО, квота)) else решта_речей).append(r)
    if тримані:
        хвіст = вибрати_зі_слота(решта_речей, квота - len(тримані), сід) if квота > len(тримані) else []
        return тримані + хвіст
    гілки = collections.defaultdict(list)
    for r in речі:
        гілки[(r.get("гілка") if isinstance(r, dict) else None) or ГІЛКА_ЯДРО].append(r)
    if len(гілки) > 1:
        return _частками_гілок(гілки, квота, сід)
    страти = collections.defaultdict(list)
    for r in речі:
        страти[_страта(r)].append(r)
    # Порядок страт і магазинів теж сіється: інакше страти однакового розміру й
    # магазини завжди йшли б в алфавітному порядку, і «хвіст» квоти діставався б
    # тим самим стратам щоразу.
    # ── ЯКІ СТРАТИ ВЛІЗУТЬ У ТІСНУ КВОТУ — ВИРІШУЄ СІД, А НЕ РОЗМІР (рядок 179) ──
    # ЩО БУЛО ЗЛАМАНО. Рядком нижче стояв сорт за розміром страти, і він
    # СКАСОВУВАВ перемішування рядком вище скрізь, де страти різного розміру:
    # стабільний сорт лишає перемішаний порядок лише СЕРЕД РІВНИХ. Кругообіг
    # бере по одній речі зі страти, тож коли квота менша за кількість страт —
    # а на тісному бюджеті це норма — у вибірку потрапляли ПЕРШІ `квота` страт,
    # тобто найбільші, і ті самі на кожному сіді. Далі всередині страти
    # `_розкидом` ставить першими min, max і медіану ціни, і ці три від сіда не
    # залежать. Разом це й давало «п'ять сідів бачать майже той самий пул»:
    # виміряно на каталог_brief (482 речі, 17 слотів, K=129) союз п'яти сідів
    # 289 речей = 60.0 %, тобто 193 речі не потрапляли до моделі ЖОДНОГО разу —
    # не через невдачу, а за побудовою. Для жінки це той самий біль, що рядок
    # 159: «Зібрати ще раз» показує ті самі речі.
    # ЩО СТАЛО. Із сідом порядок страт — це перемішування, і край квоти ріже
    # РІЗНІ страти на різних сідах. Без сіда (`сід=0`) сорт за розміром
    # лишається — це «сіда нема»: тести, CLI й база регресії дістають те саме,
    # що доти, байт у байт.
    # ЧОГО ЦЕ НЕ ЛАМАЄ. Кругообіг як був: кожна страта віддає одну річ, перш ніж
    # будь-яка віддасть другу, — сорт керував лише ПОРЯДКОМ цього першого кола,
    # а не його правилом. (Цінових опор усередині групи з 26.09 нема —
    # `_рівним_шансом`.)
    # ВИМІРЯНО (той самий пул): K=129 60.0 % → 68.0 %, K=180 77.4 % → 79.7 %,
    # K=220 85.7 % → 84.6 %. На тісній квоті — там, де й був біль, — виграш
    # найбільший; на широкій різниця в межах одного відсотка.
    ключі = _перемішати(list(страти), сід, "страти")
    if not сід:
        ключі.sort(key=lambda k: -len(страти[k]))
    впорядковані = []
    for ключ in ключі:
        магазини = collections.defaultdict(list)
        for r in страти[ключ]:
            магазини[_магазин(r)].append(r)
        імена = _перемішати(sorted(магазини), сід, "магазини")
        по_магазинах = [_рівним_шансом(магазини[м], сід) for м in імена]
        впорядковані.append(list(_по_колу(по_магазинах)))
    return [r for _, r in zip(range(квота), _по_колу(впорядковані))]


# ── СМІЛИВИЙ НАМІР — ЧАСТКОЮ КВОТИ СЛОТА, А НЕ ЧЕРГОЮ СТРАТ (ПУЛ-НАМІР, 02.10.2026) ──
# Слово власника 02.10: «Якщо є намір, пул має відображати його більш наглядно, більший
# вибір». Гілки «на межі» й «розрив» композитор дає лише під сміливим наміром
# (`composer.СМІЛИВІ_НАМІРИ`); без наміру їх у слоті нема, і зріз нижче побайтово той самий.
# ЩО БУЛО. Гілка — лише перша вісь страти, а страти віддають по речі по колу. У «верху»
# ядро має ~400 страт (тип × зона), межа — ~20, тож при квоті 40 межі діставалось ~2 місця:
# частка гілки дорівнювала частці її СТРАТ, а не тому, що жінка просила. Виміряно
# `проби/пул_намір.py` (statement, каталог_повний, сід стенда): не-ядро 7.9–9.6 % пулу,
# межа 0–4 на слот, розрив 1–6 речей на весь пул.
# ЩО СТАЛО. Квота слота (її рахує `квоти` — сума й бюджет промпту ті самі) ділиться між
# гілками частками нижче; ядро бере решту. Гілка, якій бракує речей, віддає невикористане
# ядру, і навпаки. Усередині кожної гілки — той самий переріз страт і магазинів.
# Порядок — рівномірним переплетенням гілок, а не «ядро, потім решта»: сміливі речі не
# стоять у хвості слота.
# ЧОМУ САМЕ ЦІ ЧАСТКИ — виміром, не на око (ЗАМІР-В, `проби/вирва_сміливості.py`, 30 живих вирв):
#   ДОЛЯ_МЕЖІ 0.30 — руки 3–4 (модель без коду й каталогу, вільна стилістка) кладуть поза зону
#     палітри 7 з 23 речей одягу (0.30), і це навіть без наміру; руки 1–2 з пулом коду — 6 %
#     (ідеї 94 % у зоні). Сміливий намір дістає принаймні ту частку чужих вікон, яку стилістка
#     бере сама, коли її ніщо не стримує.
#   ДОЛЯ_РОЗРИВУ 0.20 — розрив корпусу — ОДНА річ образу поза палітрою; образ рук 1–2 —
#     5.3 речі (120 образів складання ПЕР-492), тож 1/5.3 ≈ 0.19: у слоті розриву така сама
#     частка речей поза палітрою, як у образі з оголошеним розривом.
# ПІСЛЯ (`проби/пул_намір.py`, statement, 3 сцени): не-ядро 25.4–25.6 % пулу (ДО 7.9–9.6 %),
# межа 91 (ДО 30–36), розрив 16–17 у трьох слотах далеко від обличчя (ДО 1–6 в одному);
# пул під тим самим бюджетом 120 000 символів, conventional — побайтово той самий.
ГІЛКА_ЯДРО = "ядро"
ДОЛЯ_МЕЖІ = 0.30
ДОЛЯ_РОЗРИВУ = 0.20
_ДОЛІ_ГІЛОК = {"на межі": ДОЛЯ_МЕЖІ, "розрив": ДОЛЯ_РОЗРИВУ}


def _частками_гілок(гілки, квота, сід=0):
    """Квота слота, поділена між гілками (`_ДОЛІ_ГІЛОК`; ядро — решта), і переплетена.

    Кожна не-ядрова гілка бере `round(квота × частка)`, але не менше однієї речі й не більше,
    ніж має; ядро — решту. Недобір будь-якої гілки віддається іншим (спершу ядру), тож сума
    завжди `min(квота, усього речей)`. Усередині гілки — `вибрати_зі_слота` (страти,
    магазини, сід), переплетення — за рівномірною позицією `(k + ½) / n` у своїй гілці."""
    # ДОЗА БЕЗ НАМІРУ (`_доза` на речі — ціль слота, яку поставив композитор): гілка бере
    # рівно дозу, а не частку квоти — це не сміливий намір, а мала помітна добірка.
    _ціль = lambda рч: (min(int(r.get("_доза") or 0) for r in рч)
                        if all(isinstance(r, dict) and r.get("_доза") for r in рч) else None)
    скільки = {г: min(len(рч), max(1, _ціль(рч) if _ціль(рч) is not None
                                   else int(round(квота * _ДОЛІ_ГІЛОК.get(г, 0.0)))))
               for г, рч in гілки.items() if г != ГІЛКА_ЯДРО}
    _стеля = квота - (1 if гілки.get(ГІЛКА_ЯДРО) else 0)   # ядро не зникає зі слота цілком
    while sum(скільки.values()) > max(0, _стеля):
        г = max(скільки, key=lambda x: (скільки[x], x)); скільки[г] -= 1
    скільки[ГІЛКА_ЯДРО] = min(len(гілки.get(ГІЛКА_ЯДРО, ())), квота - sum(скільки.values()))
    лишок = квота - sum(скільки.values())
    for г in [ГІЛКА_ЯДРО] + sorted(x for x in скільки if x != ГІЛКА_ЯДРО):
        дод = min(лишок, len(гілки.get(г, ())) - скільки[г])
        скільки[г] += дод; лишок -= дод
    порядок = [ГІЛКА_ЯДРО] + sorted(x for x in гілки if x != ГІЛКА_ЯДРО)
    частини = {г: вибрати_зі_слота(гілки[г], скільки[г], сід) for г in порядок if скільки.get(г)}
    return переплести([частини[г] for г in порядок if г in частини])


def переплести(частини):
    """Списки, злиті рівномірно: k-та річ списку довжини n стає на позицію (k + ½) / n;
    нічия — порядком списків. Порядок усередині кожного списку не міняється."""
    злиті = [((k + 0.5) / len(рч), і, r) for і, рч in enumerate(частини) if рч
             for k, r in enumerate(рч)]
    return [r for _, _, r in sorted(злиті, key=lambda x: (x[0], x[1]))]


# ── ВАГА ОБОВ'ЯЗКОВОГО СЛОТА (17.09.2026) ────────────────────────────────────
# Квота ділила бюджет РІВНО між усіма слотами: підлога однакова, залишок
# пропорційний наявному. Для слота, який сценарій вимагає (взуття й сумка за
# `pipeline.пакет_для_моделі`, верх і низ за `structура_образу`), це не те саме,
# що для брошки: без брошки образ є, без взуття образу нема. При тісному бюджеті
# (`бюджет_речей < len(доступно)` або усічення підлог) пропорція мовчки віддавала
# місце найбагатшому слоту — а найбагатші в цьому каталозі саме периферійні
# (виміряно на каталог_brief: пояс 29, шарф 29 проти низу 2).
# ЩО РОБИТЬСЯ: квота рахується ЯК РАНІШЕ, і лише потім обов'язковий слот
# добирається до `МІН_ОБОВЯЗКОВОГО` коштом найбагатших НЕобов'язкових. Сума не
# росте ні на одиницю — стеля бюджету лишається стелею. Там, де обов'язкові слоти
# й так мають своє (стенд на каталог_повний: верх 54, низ 27, взуття 45, сумка 45),
# ця гілка не робить НІЧОГО, і зріз лишається побайтово тим самим.
# ЄДИНЕ ДЖЕРЕЛО ЧИСЛА для обох ярусів гарантії: добір кандидатів
# (`composer.добір_слота`) і вага квоти нижче. `composer.МІН_ОБОВЯЗКОВОГО` — це
# ім'я цього ж числа, а не другий літерал.
МІН_ОБОВЯЗКОВОГО = 3        # менше — слот не вибір, а єдина річ (17.09.2026)
# Поле-прапорець «цю річ зріз не має права зняти першою»: його ставить шов
# (`bridge._пакет_у_бюджет`) на речі кольору, ОБРАНОГО ЖІНКОЮ. Ім'я стоїть тут, бо
# читає його семплер, а два літерали в двох модулях розійшлись би тихо.
ПОЛЕ_УТРИМАННЯ = "_обраний_колір"


def _вага_обовязкових(квота, доступно, обовязкові):
    """Обов'язкові слоти добираються до МІН коштом найбагатших інших. Сума стала."""
    ціль = {с: min(МІН_ОБОВЯЗКОВОГО, доступно.get(с, 0)) for с in обовязкові
            if с in доступно}
    борг = {с: ц - квота.get(с, 0) for с, ц in ціль.items() if квота.get(с, 0) < ц}
    if not борг:
        return квота
    # ПО КОЛУ, А НЕ ПО ЧЕРЗІ: спершу кожен обов'язковий слот дістає ПЕРШУ річ, і
    # лише тоді хтось дістає другу. Черга «слот за слотом» на тісному бюджеті
    # віддавала три місця першому за абеткою, а решті нуль — тобто лікувала одну
    # діру, роблячи три. Це той самий обхід по колу, яким `вибрати_зі_слота`
    # тримає переріз страт.
    квота = dict(квота)
    борг = dict(борг)
    while борг:
        роздано = 0
        # найбідніший обов'язковий слот іде першим у колі: інакше слот, у якого
        # вже є одна річ, брав би другу перед тим, у кого нема жодної
        for с in sorted(борг, key=lambda x: (квота.get(x, 0), x)):
            донор = min((x for x in квота if x not in ціль and квота[x] > 0),
                        key=lambda x: (-квота[x], x), default=None)
            if донор is None:
                return квота       # віддати нема кому: бюджет менший за самі обов'язкові
            квота[донор] -= 1
            квота[с] = квота.get(с, 0) + 1
            борг[с] -= 1
            роздано += 1
        борг = {с: n for с, n in борг.items() if n > 0}
        if not роздано:
            break
    return квота


def квоти(доступно, бюджет_речей, підлога=ПІДЛОГА_СЛОТА, обовязкові=()):
    """Скільки речей дістає кожен слот.

    ІНВАРІАНТ: `sum(квоти(...).values()) <= бюджет_речей` ЗАВЖДИ. Бюджет — стеля,
    а не побажання; підлога працює лише всередині стелі.

    Підлога — спершу: слот, який не набирає підлоги, віддає все, що має, і більше
    не бере участі в дільбі. Залишок ділиться ПРОПОРЦІЙНО наявному, тож пропорції
    каталогу доїжджають до моделі, а не вирівнюються плоским числом. Залишки
    роздаються за найбільшим дробом (метод найбільшого залишку), інакше сума квот
    не сходиться з бюджетом і різниця мовчки з'їдається останнім слотом.

    ПІДЛОГА НЕ ПЕРЕВАЖУЄ БЮДЖЕТ (наряд Н-small-data-105). Тут стояло
    `лишок <= 0 → return квота`, тобто при бюджеті, меншому за суму підлог, код
    мовчки віддавав ПІДЛОГИ: `вибрати(кандидати, 1)` на чотирьох слотах давало
    80 речей, а не 1, і «мінімальна вибірка» моста була 20×слотів. Мовчазне
    перевищення стелі — рівно те, проти чого стеля й вводилась. Тепер, коли
    підлоги не влазять, бюджет ділиться пропорційно НАЯВНОМУ тим самим методом
    найбільшого залишку, що й залишок нижче."""
    if not доступно:
        return {}
    if бюджет_речей <= 0:
        return {с: 0 for с in доступно}
    _ваг = lambda к: _вага_обовязкових(к, доступно, обовязкові) if обовязкові else к
    # МЕЖА: менше однієї речі на слот. Пропорція тут уже не має що ділити —
    # оголошуємо правило явно: по одній речі найбагатшим слотам, решті нуль.
    if бюджет_речей < len(доступно):
        за_наявним = sorted(доступно, key=lambda с: (-доступно[с], с))
        зріз = {с: 0 for с in доступно}
        лишилось = бюджет_речей
        for с in за_наявним:
            if лишилось <= 0:
                break
            if доступно[с] > 0:
                зріз[с] = 1
                лишилось -= 1
        return _ваг(зріз)
    квота = {с: min(підлога, n) for с, n in доступно.items()}
    лишок = бюджет_речей - sum(квота.values())
    if лишок < 0:
        # ── УСІЧЕННЯ: ПІДЛОГА ЗМЕНШУЄТЬСЯ ОДНАКОВО ДЛЯ ВСІХ (рядок 172) ──────
        # ЩО БУЛО. Тут стояла дільба бюджету ПРОПОРЦІЙНО `доступно` — тобто в ту
        # мить, коли підлоги перестають влазити, підлога зникала НАСОВСІМ, і
        # бюджет діставався найбагатшим слотам. Перехід був стрибком: на 17
        # слотах сума підлог 302, і сусідні K по різні боки цього числа давали
        # РІЗНІ ПАКЕТИ (виміряно `проби/sempler_pidloga_172.py`, пул наряду):
        #   K=330 → верх 28, взуття 28, браслет 20, кольє 9, сережки 20
        #   K=300 → верх 74, взуття 74, браслет  4, кольє 2, сережки  6
        # Тобто зсув пулу на кілька рядків (відсічення замші зняло 86) перекидав
        # склад пакета, і дрібні слоти модель майже переставала бачити САМЕ ТОДІ,
        # коли пул великий. Пропорція каталогу — правило для ЛИШКУ (нижче), а не
        # для самого права слота бути в пакеті.
        # ЩО СТАЛО. Водоналивна дільба: шукається найбільша СПІЛЬНА підлога `f`,
        # за якої `sum(min(f, n)) <= бюджет`; кожен слот бере `min(f, n)`.
        # Отже ріжуться найбільші слоти (їх стеля `f`), а дрібні, яких менше за
        # `f`, віддають усе, що мають, — і не падають нижче підлоги, поки в
        # каталозі є кандидати. Підлога не зникає, вона зменшується — однаково
        # для всіх. Лишок після цього роздається найбільшим слотам: вони ж і
        # зрізані найдужче відносно наявного.
        # ЧОМУ ЦЕ ЗНІМАЄ І СТРИБОК K. Межа `sum(підлог)` перестає бути розривом:
        # при K трохи меншому за неї `f` = підлога − 1, а не «підлоги нема».
        сума_д = sum(доступно.values())
        if сума_д <= бюджет_речей:
            return _ваг(квота)
        _лив = lambda f: sum(min(f, n) for n in доступно.values())
        _низ, _верх = 0, підлога
        while _низ < _верх:
            _сер = (_низ + _верх + 1) // 2
            if _лив(_сер) <= бюджет_речей:
                _низ = _сер
            else:
                _верх = _сер - 1
        зріз = {с: min(_низ, n) for с, n in доступно.items()}
        решта = бюджет_речей - sum(зріз.values())
        # ЛИШОК — НАЙБІЛЬШИМ СЛОТАМ: дрібні вже віддали все, що мали, і взяти
        # більше їм нема звідки; сортування з іменем слота тримає детермінізм.
        за_наявним = sorted(доступно, key=lambda с: (-доступно[с], с))
        while решта > 0:
            _роздано = 0
            for с in за_наявним:
                if решта <= 0:
                    break
                if зріз[с] < доступно[с]:
                    зріз[с] += 1
                    решта -= 1
                    _роздано += 1
            if not _роздано:
                break
        return _ваг(зріз)
    if лишок == 0:
        return _ваг(квота)
    вільні = {с: доступно[с] - квота[с] for с in доступно if доступно[с] > квота[с]}
    if not вільні:
        return _ваг(квота)
    сума = sum(вільні.values())
    частки = {с: лишок * n / сума for с, n in вільні.items()}
    for с, ч in частки.items():
        квота[с] += min(int(ч), вільні[с])
    решта = бюджет_речей - sum(квота.values())
    if решта > 0:
        за_дробом = sorted(вільні, key=lambda с: (-(частки[с] % 1.0), с))
        for с in за_дробом:
            if решта <= 0:
                break
            if квота[с] < доступно[с]:
                квота[с] += 1
                решта -= 1
    return _ваг(квота)


def сліпота_осей(кандидати):
    """Скільки рядків не має кожної осі страти — по слотах.

    ЧОМУ ЦЕ ТУТ (наряд Н-small-data-109). `_страта` стратифікує за трьома осями,
    але мовчки підставляє "?" тому, чого нема, — тож вісь, порожня на 89 % рядків,
    працює як стала й не стратифікує НІЧОГО, а рапорт моста при цьому заявляє
    «зрізано стратифікованим семплером». Вимір 10.09.2026 на каталог_повний: без
    `тип` було 89 % сумок, 86 % прикрас, 84 % шарфів і 100 % намиста.
    Лікування — у `feed` (словник типів), а не тут: семплер не має права
    підмінювати відсутню вісь дефолтом (крок 4 наряду), він має її ПОКАЗАТИ.
    """
    звіт = {}
    for с, речі in кандидати.items():
        n = len(речі)
        звіт[с] = dict(рядків=n, страт=len({_страта(r) for r in речі}),
                       без_тип=sum(1 for r in речі if not r.get("тип")),
                       без_зона=sum(1 for r in речі if not r.get("зона")),
                       без_гілка=sum(1 for r in речі if not r.get("гілка")))
    return звіт


