def сіль(код):
    """Рядок солі за кодом (латиницею); коду нема в мапі — він сам."""
    return bytes.fromhex(СІЛЬ[код]).decode("utf-8") if код in СІЛЬ else код



def _перемішати(послідовність, сід, мітка):
    """Впорядкувати за ід і перемішати спільною політикою на місці."""
    послідовність[:] = _ПВ.порядок(послідовність, сід, мітка)
    return послідовність


def вибрати_зі_слота(речі, квота, сід=0):
    """Добирає речі слота в межах квоти, доз та утримання явного кольору."""
    речі = _ПВ.порядок(речі)
    if any(isinstance(r, dict) and "_дози" in r for r in речі):
        return _з_незалежними_дозами(речі, квота, сід)
    # Доза належить своїй гілці: мала добірка блиску не обрізає межу чи нижню смугу.
    # Нижня смуга повертає недобір інших гілок, тому навіть слот лише з неї тримає квоту.
    дози = collections.defaultdict(list)
    for r in речі:
        if isinstance(r, dict) and "_доза" in r:
            дози[_гілка_вибірки(r)].append(r)
    # Її явний колір сильніший за дозу; чинна межа утримання лишається всередині квоти.
    явні = {id(r) for r in [r for r in речі if isinstance(r, dict) and r.get(ПОЛЕ_УТРИМАННЯ)]
            [:max(0, min(МІН_ОБОВЯЗКОВОГО, квота))]} if дози else set()
    цілі = {г: min(int(r["_доза"]) for r in рч) for г, рч in дози.items()}
    без_нижньої = len(речі) - sum(map(len, дози.values())) + sum(
        min(len(рч), цілі[г]) for г, рч in дози.items() if г != "нижче смуги")
    лишити = set()
    for г, рч in дози.items():
        ціль = max(цілі[г], квота - без_нижньої) if г == "нижче смуги" else цілі[г]
        тримати = [r for r in рч if id(r) in явні]
        решта = _за_рівнями([r for r in рч if id(r) not in явні], ціль - len(тримати), сід)
        лишити.update(id(r) for r in тримати + решта)
    if дози:
        речі = [r for r in речі if not (isinstance(r, dict) and "_доза" in r) or id(r) in лишити]
    if квота >= len(речі):
        # Повний слот іде весь, з кращими рівнями першими.
        рівні = _рівні_речей(речі) if сід else {}
        if len(рівні) < 2:
            return _перемішати(list(речі), сід, сіль("whole"))
        return [r for л in sorted(рівні) for r in _перемішати(list(рівні[л]), сід, сіль("whole") + "|" + str(л))]
    # ── ОБРАНИЙ КОЛІР ПЕРЕЖИВАЄ ЗРІЗ ─────────────────────────────────────────
    # ТОЙ САМИЙ ЯРУС, ЩО Й ВАГА ОБОВ'ЯЗКОВОГО СЛОТА НИЖЧЕ, лише всередині слота:
    # там квота стерегла, щоб слот не зник, тут — щоб із слота не зникла ЄДИНА
    # річ того кольору, який назвала жінка.
    # ПОЛЕ СТАВИТЬ ТОЙ, ХТО ЗНАЄ ПРО ВИБІР (`bridge._пакет_у_бюджет`), а не
    # семплер: колір — це палітра, а тут модуль-лист, який нічого проєктного не
    # імпортує.
    # СУМА НЕ РОСТЕ: утримані входять У квоту, а не понад неї.
    тримані, решта_речей = [], []
    for r in речі:
        (тримані if (isinstance(r, dict) and r.get(ПОЛЕ_УТРИМАННЯ)
                     and len(тримані) < min(МІН_ОБОВЯЗКОВОГО, квота)) else решта_речей).append(r)
    if тримані:
        хвіст = вибрати_зі_слота(решта_речей, квота - len(тримані), сід) if квота > len(тримані) else []
        return тримані + хвіст
    гілки = collections.defaultdict(list)
    for r in речі:
        гілки[_гілка_вибірки(r)].append(r)
    if len(гілки) > 1:
        return _частками_гілок(гілки, квота, сід)
    return _за_рівнями(речі, квота, сід)


def _з_незалежними_дозами(речі, квота, сід):
    """Вибрати в межах квоти, рахуючи кожну дозу незалежно від інших ознак.

    Утриманий явний колір входить у лічбу доз. Підлога слота може перевищити
    нижню смугу лише коли речей без неї бракує, як і у звичайній вибірці.
    """
    квота = max(0, min(квота, len(речі)))
    чисті = [_ПВ.без_доз(r) for r in речі]
    оригінали = {id(ч): р for ч, р in zip(чисті, речі)}
    порядок = [оригінали[id(ч)] for ч in _за_рівнями(чисті, len(чисті), сід)]
    дози = [_ПВ.дози(r) for r in речі]
    цілі = {г: min(д[г] for д in дози if г in д) for г in {г for д in дози for г in д}}
    if "нижче смуги" in цілі:
        цілі["нижче смуги"] = max(цілі["нижче смуги"],
                                   min(квота, ПІДЛОГА_СЛОТА) - sum("нижче смуги" not in д for д in дози))
    обрані = [r for r in порядок if r.get(ПОЛЕ_УТРИМАННЯ)][:min(МІН_ОБОВЯЗКОВОГО, квота)]
    лічба = collections.Counter(г for r in обрані for г in _ПВ.дози(r))
    взяті = {id(r) for r in обрані}

    def можна(r):
        """Чи річ не перевищить незалежні стелі доз."""
        return id(r) not in взяті and all(лічба[г] < цілі[г] for г in _ПВ.дози(r))

    def додати(r):
        """Додати річ один раз і зарахувати всі її ознаки."""
        обрані.append(r)
        взяті.add(id(r))
        лічба.update(_ПВ.дози(r).keys())

    # Спершу забезпечуємо рідші цілі: одна річ може виконати кілька незалежних доз.
    for г in sorted(цілі, key=lambda г: (sum(г in д for д in дози) / max(1, цілі[г]), г)):
        for r in порядок:
            if len(обрані) >= квота or лічба[г] >= цілі[г]:
                break
            if г in _ПВ.дози(r) and можна(r):
                додати(r)
    придатні = [r for r in порядок if можна(r)]
    чисті = [_ПВ.без_доз(r) for r in придатні]
    оригінали = {id(ч): р for ч, р in zip(чисті, придатні)}
    for ч in вибрати_зі_слота(чисті, квота - len(обрані), сід):
        r = оригінали[id(ч)]
        if можна(r):
            додати(r)
    # Квоту не наповнюємо додатковими речами дозованої ознаки, коли її ціль уже виконана.
    return переплести([обрані[:min(МІН_ОБОВЯЗКОВОГО, квота)],
                       обрані[min(МІН_ОБОВЯЗКОВОГО, квота):]])


ПОЛЕ_РАНГУ = "_ранг_пізній"


def _ранги(речі):
    """Читає пізні ключі з рядків пакета."""
    return [tuple(r.get(ПОЛЕ_РАНГУ) or ()) if isinstance(r, dict) else () for r in речі]


def _рівні_речей(речі):
    """Групує речі для показу повного слота в порядку рівнів."""
    рівні = collections.defaultdict(list)
    for річ, рівень in zip(речі, _рівні(_ранги(речі))):
        рівні[рівень].append(річ)
    return рівні


def _за_рівнями(речі, квота, сід):
    """Добирає зі слота за пізніми ключами, з рівним шансом у рівні."""
    # Перед цим речі вже впорядковано за їхніми сталими ідентифікаторами.
    ранги = dict(enumerate(_ранги(речі)))
    return [речі[і] for і in _добрати(ранги, квота, сід)]


# Сміливі гілки беруть визначену частку квоти слота. Недобір повертається
# в інші гілки, а їхні готові добірки переплітаються для показу.
# ЧОМУ САМЕ ЦІ ЧАСТКИ — виміром, не на око:
#   ДОЛЯ_МЕЖІ 0.30 — руки 3–4 (модель без коду й каталогу, вільна стилістка) кладуть поза зону
#     палітри 7 з 23 речей одягу (0.30), і це навіть без наміру; руки 1–2 з пулом коду — 6 %
#     (ідеї 94 % у зоні). Сміливий намір дістає принаймні ту частку чужих вікон, яку стилістка
#     бере сама, коли її ніщо не стримує.
#   ДОЛЯ_РОЗРИВУ 0.20 — розрив корпусу — ОДНА річ образу поза палітрою; образ рук 1–2 —
#     5.3 речі (120 образів складання ПЕР-492), тож 1/5.3 ≈ 0.19: у слоті розриву така сама
#     частка речей поза палітрою, як у образі з оголошеним розривом.
ГІЛКА_ЯДРО = "ядро"
ДОЛЯ_МЕЖІ = 0.30
ДОЛЯ_РОЗРИВУ = 0.20
_ДОЛІ_ГІЛОК = {"на межі": ДОЛЯ_МЕЖІ, "розрив": ДОЛЯ_РОЗРИВУ}


def _гілка_вибірки(річ):
    """Повертає службову гілку дози або гілку палітри."""
    return (річ.get("_гілка_дози") or річ.get("гілка") or ГІЛКА_ЯДРО) if isinstance(річ, dict) else ГІЛКА_ЯДРО


def _частками_гілок(гілки, квота, сід=0):
    """Квота слота, поділена між гілками (`_ДОЛІ_ГІЛОК`; ядро — решта), і переплетена.

    Кожна не-ядрова гілка бере `round(квота × частка)`, але не менше однієї речі й не більше,
    ніж має; ядро — решту. Недобір будь-якої гілки віддається іншим (спершу ядру), тож сума
    завжди `min(квота, усього речей)`. Кожна гілка добирає за рівнями;
    переплетення — за рівномірною позицією `(k + ½) / n` у своїй гілці."""
    # ДОЗА БЕЗ НАМІРУ (`_доза` на речі — ціль слота, яку поставив композитор): гілка бере
    # рівно дозу, а не частку квоти — це не сміливий намір, а мала помітна добірка.
    _ціль = lambda рч: (min(int(r["_доза"]) for r in рч)
                        if all(isinstance(r, dict) and "_доза" in r for r in рч) else None)
    скільки = {г: min(len(рч), max(1, _ціль(рч) if _ціль(рч) is not None
                                   else round(квота * _ДОЛІ_ГІЛОК.get(г, 0.0))))
               for г, рч in гілки.items() if г != ГІЛКА_ЯДРО}
    _стеля = квота - (1 if гілки.get(ГІЛКА_ЯДРО) else 0)   # ядро не зникає зі слота цілком
    while sum(скільки.values()) > max(0, _стеля):
        г = max(скільки, key=lambda x: (скільки[x], x)); скільки[г] -= 1
    скільки[ГІЛКА_ЯДРО] = min(len(гілки.get(ГІЛКА_ЯДРО, ())), квота - sum(скільки.values()))
    лишок = квота - sum(скільки.values())
    for г in [ГІЛКА_ЯДРО] + sorted(x for x in скільки if x != ГІЛКА_ЯДРО):
        дод = min(лишок, len(гілки.get(г, ())) - скільки[г])
        скільки[г] += дод; лишок -= дод
    порядок = [ГІЛКА_ЯДРО] + sorted(x for x in гілки if x != ГІЛКА_ЯДРО)
    частини = {г: вибрати_зі_слота(гілки[г], скільки[г], сід) for г in порядок if скільки.get(г)}
    return переплести([частини[г] for г in порядок if г in частини])


