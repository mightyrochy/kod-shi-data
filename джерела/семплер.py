def сліпота_заявами(звіт, поріг=0.10):
    """Заяви рапорту (`внутрішня_мова.заява`): осі, сліпі понад `поріг`, і в яких слотах — або [].
    Доти тут складалось речення («вісь «тип» сліпа на 89 % пулу, у слотах сумка 89 %…»), яке
    `міст_пакет` доліплював до `стеля.чому` (ВМ-3а, рядок 247): ті самі числа — значеннями заяви."""
    import внутрішня_мова as _ВМ
    заяви = []
    for вісь in ("тип", "зона", "гілка"):
        ключ = "без_" + вісь
        сліпі = sorted(((с, з[ключ] / з["рядків"]) for с, з in звіт.items()
                        if з["рядків"] and з[ключ] / з["рядків"] > поріг),
                       key=lambda п: -п[1])
        if сліпі:
            усього = sum(з[ключ] for з in звіт.values())
            рядків = sum(з["рядків"] for з in звіт.values()) or 1
            заяви.append(_ВМ.заява("pool_stratum_axis_blind", axis=ВІСЬ_КОД[вісь],
                                   share=round(100.0 * усього / рядків),
                                   kinds={_ВМ.код_або_невідомо("slot", с): round(100.0 * ч) for с, ч in сліпі}))
    return заяви


def вибрати(кандидати, бюджет_речей, підлога=ПІДЛОГА_СЛОТА, сід=0, звіт=None,
            обовязкові=()):
    """Головний вхід: {слот: [речі]} + бюджет речей → {слот: [речі]}.

    `звіт` — необовʼязковий словник, який заповнюється діагностикою `сліпота_осей`
    по ВХІДНОМУ пулу плюс роздана квота. Вихід лишається {слот: [речі]}: інакше
    кожен викликач мусив би знати про звіт, а знати про нього має лише той, хто
    пише рапорт про зріз."""
    доступно = {с: len(v) for с, v in кандидати.items()}
    к = квоти(доступно, бюджет_речей, підлога, обовязкові)
    if звіт is not None:
        звіт.clear()
        звіт.update(сліпота_осей(кандидати))
        for с in звіт:
            звіт[с]["квота"] = к.get(с, 0)
    return {с: вибрати_зі_слота(кандидати[с], к.get(с, 0), сід) for с in кандидати}
