"""збирач_промптів.py — промпт моделі з ОГОЛОШЕННЯ задачі, одним шаблоном для всіх задач.

ЧОМУ ЦЕ Є. Власник, 25.09.2026: «не легше, замість того щоб чистити зламані
промпти, написати логіку створення нових чистих, точних, зрозумілих і всеосяжних
промптів для кожної окремої ітерації чи задачі?». Доти кожен промпт був ТЕКСТОМ, до
якого місяцями дописувались абзаци проти окремих провалів, приклади з тестів і
пояснення для людей. Ноутбук 25.09 (PR #304, П.6): 10 фраз жінок, 24 названі факти;
з промптом паспорта продукту MamayLM вигадала 28 і 25 фактів (серед них «без
підборів» — прямо з прикладу промпту), з коротким промптом — 0–1.

ОГОЛОШЕННЯ — ДАНІ, А НЕ ТЕКСТ (`Оголошення`):
  роль        одне речення: хто модель у цьому виклику;
  вхід        поля, які може нести виклик (`Поле`): що це і, коли треба, що з ним
              робити. У промпт іде лише поле, яке в ЦЬОМУ виклику є й не порожнє,
              і його рядок — разом із ним. Рядок `без` іде саме тоді, коли поля
              нема. Поле з `треба=True` мусить бути: без нього — ValueError. Поле
              даних, якого оголошення не називає, у промпт не йде зовсім;
  правила     що зробити: рядки самої задачі;
  вихід       імʼя схеми з `протокол.СХЕМИ` — ТІЄЇ САМОЇ, якою код перевіряє
              відповідь. Скелет рахує `пакет_моделі.скелет_схеми`; `поля_виходу`
              лише підписують його листки словами. Шлях, якого в схемі нема, —
              ValueError: підпис і перевірка не мають права розійтися;
  межі        ключі закритого переліку `МЕЖІ` — загальні правила всіх задач.

ЗАБОРОНЕНО в оголошеннях: приклади-фрази (особливо з тестів), абзаци під окремий
випадок і пояснення для людей. Їм місце в коментарях коду над оголошенням.

ШАБЛОН — один для всіх задач (`зібрати`), порядок розділів сталий:
  {"версія": "1",                       ← задачам протоколу (вихід — схема з СХЕМИ)
   <поля входу — порядком оголошення>,
   "завдання": {"роль", "вхід", "правила", "межі", "мова", "відповідь",
                "схема_відповіді"}}      ← скелет — останнім
Дані — першими, завдання — останнім, скелет — останнім у ньому: це те, що модель
читає перед першим словом відповіді (Т-7: коли після скелета стояв вхід, модель
починала переписувати вхід). `завдання.відповідь` — імʼя схеми: за ним показ,
заглушка стенда й розбір знають, яку відповідь чекати.

ДЕ ЖИВУТЬ ОГОЛОШЕННЯ — поруч із кодом своєї задачі (`розбір_відповідей.ОПИС`,
`повнота_образу.ВИБІР`), а не тут: паралельні сесії правлять кожна свій модуль.
Тут — лише формат, шаблон і закритий перелік меж.
"""
from dataclasses import dataclass, field

import протокол as _ПР
from пакет_моделі import скелет_схеми

# ── МЕЖІ: ЗАКРИТИЙ ПЕРЕЛІК ЗАГАЛЬНИХ ПРАВИЛ ─────────────────────────────────
# Одне правило — один текст на всю систему: оголошення називає ключ, а не пише
# свою редакцію «не вигадуй». Нове правило сюди — лише загальне, що стосується
# будь-якої задачі; правило однієї задачі стоїть у її `правила`.
МЕЖІ = {
    "лише_вхід": "Спирайся лише на вхід: чого в ньому нема, не вигадуй.",
    "невідомо": "Чого не знаєш — «невідомо», null або порожній список, як дозволяє схема.",
    "для_неї": ("Текст для неї — на «ти» і людськими словами: без номерів речей, id, "
                "hex-кодів і markdown."),
    "без_чисел_тіла": "Не називай чисел світлоти й типів фігури і не кажи, що мала обмеження.",
}
# Мова відповіді — поле шаблону, а не межа на вибір: українською відповідає кожна задача.
МОВА = "українська"
# Останній рядок меж кожної задачі з JSON-відповіддю — форма відповіді, одразу перед скелетом.
ФОРМА_JSON = "Відповідь — лише один JSON-обʼєкт за «схема_відповіді», без пояснень і без ```."


@dataclass(frozen=True)
class Поле:
    """Одне поле входу.

    `шлях` — ключ даних («образ») або шлях усередину поля («образ.речі[].фото_номери»;
    `[]` — кожен елемент списку). Значення в повідомлення дає лише поле верхнього рівня;
    поле зі шляхом додає свій рядок у «вхід» і нічого більше.
    `що` — що це (для моделі); `як` — що з ним робити, коли воно є; `без` — рядок,
    який іде, коли поля нема; `треба` — без цього поля виклику не буває.
    """
    шлях: str
    що: str
    як: str = ""
    без: str = ""
    треба: bool = False


@dataclass(frozen=True)
class Оголошення:
    """Задача моделі даними: роль, вхід, правила, вихід (схема протоколу), межі."""
    задача: str
    роль: str
    вхід: tuple
    правила: tuple
    вихід: str
    поля_виходу: dict = field(default_factory=dict)
    межі: tuple = ()


def _значення(дані, шлях):
    """Усі значення за шляхом «а.б[].в» у даних; чого нема — того в списку нема."""
    вузли = [дані]
    for ч in шлях.split("."):
        список = ч.endswith("[]")
        ключ = ч[:-2] if список else ч
        далі = []
        for в in вузли:
            if isinstance(в, dict) and ключ in в:
                х = в[ключ]
                if not список:
                    далі.append(х)
                elif isinstance(х, (list, tuple)):
                    далі.extend(х)
        вузли = далі
    return вузли


def _не_порожнє(в):
    """Чи несе значення щось: None, порожній рядок, список чи словник — ні; 0 і False — так."""
    if в is None:
        return False
    if isinstance(в, str):
        return bool(в.strip())
    if isinstance(в, (list, tuple, dict)):
        return bool(в)
    return True


def _підпис(листок, текст):
    """Підпис листка: «<тип>» → «<текст>»; перелік значень («a|b») лишається — «a|b — текст»."""
    if isinstance(листок, str) and листок and not листок.startswith("<"):
        return "%s — %s" % (листок, текст)
    return "<%s>" % текст


def _підписати(скелет, шлях, текст, задача):
    """Листок скелета за шляхом «а.б[].в» → «<текст>». Шлях повз схему — ValueError."""
    вузол, ч = скелет, шлях.split(".")
    for і, крок in enumerate(ч):
        список = крок.endswith("[]")
        ключ = крок[:-2] if список else крок
        if not isinstance(вузол, dict) or ключ not in вузол:
            raise ValueError("%s: поля виходу «%s» у схемі нема" % (задача, шлях))
        if і == len(ч) - 1 and not список:
            if isinstance(вузол[ключ], list) and вузол[ключ] and not isinstance(вузол[ключ][0], (dict, list)):
                вузол[ключ] = [_підпис(вузол[ключ][0], текст)]
            elif isinstance(вузол[ключ], (dict, list)):
                raise ValueError("%s: «%s» — не листок; підписуй його поля" % (задача, шлях))
            else:
                вузол[ключ] = _підпис(вузол[ключ], текст)
            return
        вузол = вузол[ключ]
        if список:
            if not isinstance(вузол, list) or not вузол:
                raise ValueError("%s: «%s» — не список у схемі" % (задача, крок))
            вузол = вузол[0]


def скелет(о):
    """Скелет відповіді задачі: зі схеми протоколу, листки — підписами `поля_виходу`."""
    if о.вихід not in _ПР.СХЕМИ:
        raise ValueError("%s: схеми «%s» у протоколі нема" % (о.задача, о.вихід))
    с = скелет_схеми(_ПР.СХЕМИ[о.вихід])
    for шлях, текст in о.поля_виходу.items():
        _підписати(с, шлях, текст, о.задача)
    return с


def зібрати(о, дані):
    """Оголошення + дані ЦЬОГО виклику → повідомлення моделі (dict) шаблоном модуля.

    З `дані` береться лише те, що оголошення називає у `вхід`, решта в промпт не йде.
    Значення полів — ті самі обʼєкти, що в `дані` (не копії): повідомлення перевіряє
    схема протоколу, і рядком його робить викликач (`json.dumps`).
    """
    невідомі = [к for к in о.межі if к not in МЕЖІ]
    if невідомі:
        raise ValueError("%s: меж %s у переліку нема" % (о.задача, невідомі))
    с = скелет(о)
    вих, рядки = {"версія": _ПР.ВЕРСІЯ}, []
    for п in о.вхід:
        є = any(_не_порожнє(в) for в in _значення(дані or {}, п.шлях))
        if п.треба and not є:
            raise ValueError("%s: без поля «%s» цього виклику не буває" % (о.задача, п.шлях))
        if not є:
            if п.без:
                рядки.append(п.без)
            continue
        if "." not in п.шлях and not п.шлях.endswith("[]"):
            вих[п.шлях] = дані[п.шлях]
        імʼя = п.шлях.split(".")[-1].replace("[]", "")
        рядки.append("«%s» — %s" % (імʼя, п.що) + ("; %s" % п.як if п.як else ""))
    вих["завдання"] = {
        "роль": о.роль,
        "вхід": рядки,
        "правила": list(о.правила),
        "межі": [МЕЖІ[к] for к in о.межі] + [ФОРМА_JSON],
        "мова": МОВА,
        "відповідь": о.вихід,
        "схема_відповіді": с,
    }
    return вих
