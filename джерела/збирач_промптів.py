def коди_заяв(дані):
    """Усі коди заяв у даних виклику — порядком першої появи (обхід у глибину). Заява на
    дроті — код рядком або `{код: значення}` (`дріт_моделі.заяви`); повна форма
    `{code, values}` читається теж."""
    вих = []
    def _код(x):
        if isinstance(x, str):
            return [x]
        if isinstance(x, dict):
            к = [x["code"]] if isinstance(x.get("code"), str) else [к for к in x if isinstance(к, str)][:1]
            зн = (x.get("values") if "code" in x else x.get(к[0])) if к else None
            if к and к[0] in ЗНАЧЕННЯ_КОДАМИ and isinstance(зн, dict):
                к += [у for п in ЗНАЧЕННЯ_КОДАМИ[к[0]] for у in (зн.get(п) or []) if isinstance(у, str)]
            return к
        return []
    def _обхід(в):
        if isinstance(в, dict):
            for к, v in в.items():
                if к in КЛЮЧІ_ЗАЯВ and isinstance(v, list):
                    for x in v:
                        вих.extend(_код(x))
                    continue
                if к in КЛЮЧІ_ПУНКТІВ:
                    for x in (v.values() if isinstance(v, dict) else [v]):
                        вих.extend(п for п in (x if isinstance(x, list) else [])
                                   if isinstance(п, str) and _КОД_ПУНКТУ.fullmatch(п))
                    continue
                _обхід(v)
        elif isinstance(в, (list, tuple)):
            for v in в:
                _обхід(v)
    _обхід(дані)
    return list(dict.fromkeys(вих))
