@dataclass(frozen=True)
class Поле:
    """Одне поле входу.

    `шлях` — ключ даних («образ») або шлях усередину поля («образ.речі[].фото_номери»;
    `[]` — кожен елемент списку). Значення в повідомлення дає лише поле верхнього рівня;
    поле зі шляхом додає свій рядок у «вхід» і нічого більше.
    `що` — що це (для моделі); `як` — що з ним робити, коли воно є; `без` — рядок,
    який іде, коли поля нема; `треба` — без цього поля виклику не буває.
    """
    шлях: str
    що: str
    як: str = ""
    без: str = ""
    треба: bool = False


@dataclass(frozen=True)
class Оголошення:
    """Задача моделі даними: роль, вхід, правила, вихід (схема протоколу), межі."""
    задача: str
    роль: str
    вхід: tuple
    правила: tuple
    вихід: str
    поля_виходу: dict = field(default_factory=dict)
    межі: tuple = ()
    # ВЛАСНИЙ СКЕЛЕТ ЗАДАЧІ (паспорт, 25.09.2026): відповідь, яку розбирає код самої задачі, а
    # не схема протоколу (`паспорт_з_json` читає ключі `СХЕМА_ПАСПОРТА`). Тоді `вихід` — лише
    # імʼя задачі в «відповідь», «версії» протоколу в повідомленні нема, а скелет — цей словник.
    скелет: dict = None
    # МОВА ПРОМПТА (26.09.2026, CLAUDE.md п.12): «uk» — задачі, писані до рішення власника;
    # «en» — англійський шаблон (`КЛЮЧІ_EN`, `МЕЖІ_EN`). Тексти ролі, входу й правил задача
    # пише тією самою мовою, що й шаблон.
    мова_промпту: str = "uk"
    # ВИД ВІДПОВІДІ (П-1, 26.09.2026): «json» — схема й скелет, як доти; «текст» і
    # «картинка» — ключі `ФОРМИ_EN` (див. шапку модуля).
    відповідь_як: str = "json"


def _значення(дані, шлях):
    """Усі значення за шляхом «а.б[].в» у даних; чого нема — того в списку нема."""
    вузли = [дані]
    for ч in шлях.split("."):
        список = ч.endswith("[]")
        ключ = ч[:-2] if список else ч
        далі = []
        for в in вузли:
            if isinstance(в, dict) and ключ in в:
                х = в[ключ]
                if not список:
                    далі.append(х)
                elif isinstance(х, (list, tuple)):
                    далі.extend(х)
        вузли = далі
    return вузли


def _не_порожнє(в):
    """Чи несе значення щось: None, порожній рядок, список чи словник — ні; 0 і False — так."""
    if в is None:
        return False
    if isinstance(в, str):
        return bool(в.strip())
    if isinstance(в, (list, tuple, dict)):
        return bool(в)
    return True


def _підпис(листок, текст):
    """Підпис листка: «<тип>» → «<текст>»; перелік значень («a|b») лишається — «a|b — текст»."""
    if isinstance(листок, str) and листок and not листок.startswith("<"):
        return "%s — %s" % (листок, текст)
    return "<%s>" % текст


def _підписати(скелет, шлях, текст, задача):
    """Листок скелета за шляхом «а.б[].в» → «<текст>». Шлях повз схему — ValueError."""
    вузол, ч = скелет, шлях.split(".")
    for і, крок in enumerate(ч):
        список = крок.endswith("[]")
        ключ = крок[:-2] if список else крок
        if not isinstance(вузол, dict) or ключ not in вузол:
            raise ValueError("%s: поля виходу «%s» у схемі нема" % (задача, шлях))
        if і == len(ч) - 1 and not список:
            if isinstance(вузол[ключ], list) and вузол[ключ] and not isinstance(вузол[ключ][0], (dict, list)):
                вузол[ключ] = [_підпис(вузол[ключ][0], текст)]
            elif isinstance(вузол[ключ], (dict, list)):
                raise ValueError("%s: «%s» — не листок; підписуй його поля" % (задача, шлях))
            else:
                вузол[ключ] = _підпис(вузол[ключ], текст)
            return
        вузол = вузол[ключ]
        if список:
            if not isinstance(вузол, list) or not вузол:
                raise ValueError("%s: «%s» — не список у схемі" % (задача, крок))
            вузол = вузол[0]


def скелет(о):
    """Скелет відповіді задачі: зі схеми протоколу (або власний `скелет`), листки — підписами
    `поля_виходу`."""
    if о.скелет is not None:
        с = _copy.deepcopy(о.скелет)
        for шлях, текст in о.поля_виходу.items():
            _підписати(с, шлях, текст, о.задача)
        return с
    from пакет_моделі import скелет_схеми   # ліниво: `пакет_моделі` імпортує `паспорт_нагоди`
    if о.вихід not in _ПР.СХЕМИ:
        raise ValueError("%s: схеми «%s» у протоколі нема" % (о.задача, о.вихід))
    с = скелет_схеми(_ПР.СХЕМИ[о.вихід])
    for шлях, текст in о.поля_виходу.items():
        _підписати(с, шлях, текст, о.задача)
    return с


def зібрати(о, дані, мова_тексту=None):
    """Оголошення + дані ЦЬОГО виклику → повідомлення моделі (dict) шаблоном модуля.

    З `дані` береться лише те, що оголошення називає у `вхід`, решта в промпт не йде.
    Значення полів — ті самі обʼєкти, що в `дані` (не копії): повідомлення перевіряє
    схема протоколу, і рядком його робить викликач (`json.dumps`).
    `мова_тексту` — мова вільного тексту відповіді англійської задачі (типово `МОВА_EN`);
    українська задача відповідає українською завжди, і параметр її не чіпає.
    """
    en = о.мова_промпту == "en"
    межі, форма, к = (МЕЖІ_EN, ФОРМА_JSON_EN, КЛЮЧІ_EN) if en else (МЕЖІ, ФОРМА_JSON, {})
    ключ = lambda с: к.get(с, с)
    невідомі = [м for м in о.межі if м not in межі]
    if невідомі:
        raise ValueError("%s: меж %s у переліку нема" % (о.задача, невідомі))
    json_ = о.відповідь_як == "json"
    if not json_:
        if not en or о.відповідь_як not in ФОРМИ_EN:
            raise ValueError("%s: відповіді «%s» у переліку форм англійського шаблону нема"
                             % (о.задача, о.відповідь_як))
        форма = ФОРМИ_EN[о.відповідь_як]
    с = скелет(о) if json_ else None
    вих, рядки = ({ключ("версія"): _ПР.ВЕРСІЯ} if о.скелет is None and json_ else {}), []
    for п in о.вхід:
        є = any(_не_порожнє(в) for в in _значення(дані or {}, п.шлях))
        if п.треба and not є:
            raise ValueError("%s: без поля «%s» цього виклику не буває" % (о.задача, п.шлях))
        if not є:
            if п.без:
                рядки.append(п.без)
            continue
        if "." not in п.шлях and not п.шлях.endswith("[]"):
            вих[п.шлях] = дані[п.шлях]
        імʼя = п.шлях.split(".")[-1].replace("[]", "")
        рядок = ("\"%s\" — %s" if en else "«%s» — %s") % (імʼя, п.що) + ("; %s" % п.як if п.як else "")
        if рядок not in рядки:        # два шляхи до одного поля (`а[].x`, `б[].x`) — один рядок (П-1)
            рядки.append(рядок)
    вих[ключ("завдання")] = {
        ключ("роль"): о.роль,
        ключ("вхід"): рядки,
        ключ("правила"): list(о.правила),
        ключ("межі"): [межі[м] for м in о.межі] + [форма],
        ключ("мова"): (мова_тексту or МОВА_EN) if en else МОВА,
        ключ("відповідь"): о.вихід,
        ключ("схема_відповіді"): с,
    }
    if not json_:
        вих[ключ("завдання")].pop(ключ("схема_відповіді"))
    if о.відповідь_як == "картинка":
        вих[ключ("завдання")].pop(ключ("мова"))
    return вих
