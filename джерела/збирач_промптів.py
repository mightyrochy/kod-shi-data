def _значення(дані, шлях):
    """Усі значення за шляхом «а.б[].в» у даних; чого нема — того в списку нема. Таблицю
    (`таблиця`) крок «[]» читає записами, як перелік."""
    вузли = [дані]
    for ч in шлях.split("."):
        список = ч.endswith("[]")
        ключ = ч[:-2] if список else ч
        далі = []
        for в in вузли:
            if isinstance(в, dict) and ключ in в:
                х = в[ключ]
                if not список:
                    далі.append(х)
                else:
                    х = рядки_таблиці(х)
                    if isinstance(х, (list, tuple)):
                        далі.extend(х)
