# Фронтальна проєкція. Тіло — кусково-лінійний профіль ширини за вимірами картки
# людини (обхвати / π ≈ ширина; корпус тримає height_cm і shape_ratios).
#
# ВИСОТА РІВНЯ — ОРІЄНТИР З ОБМІРУ, А НЕ ЧАСТКА, ЯКУ ПОСТАВИЛА СЕСІЯ (корінь
# `Е3-одна-величина`, рішення менеджера 06.11 «орієнтири тіла», п.1–4). Ім'я рівня
# означає один орієнтир для форми, шаблону, правил і брифу: талія — природна талія,
# найменший обхват тулуба (тема-1 §2.1); коліно — середина наколінка (тема-12: «the
# crease should bisect the kneecap»); литка — найширше місце (K-SHO-05, рішення п.7 п.3);
# груди, стегна — найвипукліше місце; високе стегно — 18 см під природною талією (§2.1).
# Частка рівня — СЕРЕДНЄ того самого орієнтира в обмірі жінок, а розкид — похибка
# рівня; обидва числа — один запис `похибка_вимірів_тіла` (вид «рівень», з джерелом і
# стовпцем обміру), тут копії нема. Застосовується до РЕАЛЬНИХ сантиметрів цієї людини.
# ДО (шаблон без посилань): талія 0.620 — на 1.99 SD нижче природної талії й на 1.35 SD
# вище пупка, жодного орієнтира; коліно 0.285 — латеральний надвиросток стегна, а не
# наколінок; високе стегно 0.575 часткою зросту, хоча база ставить його відстанню.
#
# ЛІНІЯ ПЛЕЧА І ОБХВАТ ПЛЕЧЕЙ — ДВІ ВЕЛИЧИНИ (рішення менеджера 13.11, 14650): «лінія_плеча» — акроміон, де сидить
# плечовий шов і звідки починається верх речі (тема-1 §13); «плечі» — рівень обхвату плечей форми, середина
# дельтоподібних м'язів (ANSUR II Shoulder Circumference), — нижче акроміона, висоти його обмір не дає: запис
# «невідомо» між акроміоном і пахвою, вузол профілю — на пахві (нижня межа). Ширини лінія плеча не має (обхвату
# на ній форма не питає), тож вузлом профілю вона не стає: її висота — лише в `висоти_рівнів`.
ПОРЯДОК_РІВНІВ = ("маківка", "підборіддя", "лінія_плеча", "плечі", "груди", "талія", "високе_стегно",
                  "стегна", "пах", "коліно", "литка", "щиколотка", "підлога")   # згори вниз
РІВНІ_БЕЗ_ШИРИНИ = ("лінія_плеча",)
ВУЗЛИ_ПРОФІЛЮ = tuple(nm for nm in ПОРЯДОК_РІВНІВ if nm not in РІВНІ_БЕЗ_ШИРИНИ)   # рівні з шириною тіла

# Тема-1 §2.1: «roughly 7 inches / 18 cm below the natural waist» — високе стегно
# означене ВІДСТАННЮ від природної талії, не часткою зросту; тож похибка його рівня —
# похибка рівня талії (рішення 06.11, п.2), і рівень стоїть за талією цього тіла.
ВИСОКЕ_СТЕГНО_ПІД_ТАЛІЄЮ_СМ = 18.0

# РІВЕНЬ «НЕВІДОМО» У ПРОФІЛІ (корінь `Е3-одна-величина`, п.7; рішення 06.11 «орієнтири тіла», п.1, п.4): висоти
# підборіддя й найвужчого місця щиколотки обмір не дає — запис реєстру «невідомо» (`середнє` None), і числа без
# джерела (раніше шаблон 0.870 і 0.060) тут нема. Читачі профілю (`fit.тіло`, інтерполятори ширини, краї речей за
# словом) висоти «невідомо» ще не вміють (рядок дошки 13896), тож вузол профілю стоїть на НИЖНІЙ МЕЖІ запису — висоті
# визнаного орієнтира, вище якого рівень певно лежить (щиколотка — кісточка, підборіддя — сьомий шийний хребець; ANSUR
# II). Це не «висота рівня»: рівень лежить вище, на невідому висоту, а вузол означає лише «не нижче». Похибка рівня
# лишається «невідомо» (`val` None) — читачі, що порівнюють з рівнем, його не судять.
def запис_рівня(назва):
    """Запис рівня з `похибка_вимірів_тіла`: середнє (частка зросту), розкид, джерело, стовпець обміру."""
    return _ПОХ.запис("рівень", назва)


def _частка(назва):
    """Частка зросту вузла профілю: середнє запису; високе стегно — None (стоїть відстанню від талії); рівень
    «невідомо» — нижня межа запису. Запис «невідомо» без нижньої межі — ValueError, а не вигадане число."""
    if назва == "високе_стегно":
        return None
    з = запис_рівня(назва)
    if з["середнє"] is not None:
        return з["середнє"]
    межа = з["нижня_межа"]
    if межа is None:
        raise ValueError(f"рівень «{назва}»: запис «невідомо» без нижньої межі — вузлу профілю нема на чому стати")
    return межа["середнє"]


def рівні_на_нижній_межі():
    """Рівні, чий вузол профілю стоїть на нижній межі запису, бо висоту самого рівня обмір не дає."""
    return tuple(nm for nm in ПОРЯДОК_РІВНІВ if nm != "високе_стегно" and запис_рівня(nm)["середнє"] is None)


РІВНІ = [(nm, _частка(nm)) for nm in ПОРЯДОК_РІВНІВ]


def висоти_рівнів(зріст_см):
    """{рівень: висота над підлогою, см} цього зросту: частка запису × зріст; високе стегно —
    `ВИСОКЕ_СТЕГНО_ПІД_ТАЛІЄЮ_СМ` під природною талією.

    Коли 18 см під талією не лишаються над стегнами (зріст нижче ≈132 см: 0.6483·H − 18 ≤
    0.5118·H), означення високого стегна на цьому тілі не стоїть — це ValueError, а не
    рівень, що перетнув стегна й тихо зламав порядок інтерполяції (рядок дошки 13896)."""
    H = {nm: (ч * зріст_см if ч is not None else None) for nm, ч in РІВНІ}
    H["високе_стегно"] = H["талія"] - ВИСОКЕ_СТЕГНО_ПІД_ТАЛІЄЮ_СМ
    if not H["стегна"] < H["високе_стегно"]:
        raise ValueError(f"зріст {зріст_см}: {ВИСОКЕ_СТЕГНО_ПІД_ТАЛІЄЮ_СМ:g} см під природною талією "
                         f"({H['талія']:.1f} см) — не над стегнами ({H['стегна']:.1f} см); означення "
                         "високого стегна (тема-1 §2.1) на цьому тілі не стоїть")
    return H
