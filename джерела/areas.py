def видимі(masks, порядок):
    """Оклюзія: пальто ховає светр. `порядок` — знизу вгору (останній перекриває всіх).
    Маска речі подається ПОВНОЮ (яка вона є на тілі), видиме обчислюється тут —
    інакше не можна зняти пальто й перерахувати стан «у приміщенні» (K-WEA-02)."""
    вид = {}
    for i, nm in enumerate(порядок):
        зверху = set().union(*[masks[o] for o in порядок[i+1:] if o in masks]) if i+1 < len(порядок) else set()
        вид[nm] = set(masks.get(nm, set())) - зверху
    return вид

def голова(face_mask):
    """Висота голови в пікселях — з маски обличчя. Потрібна як одиниця відстані:
    корпус міряє приобличчеву зону «радіусом ~однієї голови», а не в сантиметрах."""
    if not face_mask: return None
    ys = [p[1] for p in face_mask]
    return max(1, max(ys) - min(ys))

def смуга_обличчя(face_mask, радіусів=1.0):
    """Пікселі приобличчевої зони — одна висота голови від краю обличчя (корпус)."""
    h = голова(face_mask)
    if not h: return None, None
    fx = [p[0] for p in face_mask]; fy = [p[1] for p in face_mask]
    cx, cy = (min(fx)+max(fx))/2, (min(fy)+max(fy))/2
    R = радіусів*h + h/2
    return (cx, cy), R

def near_share(pixels, face_mask, поле_смуги, радіусів=1.0):
    """ВИПРАВЛЕНО ПІСЛЯ НАСКРІЗНОГО ПРОГОНУ. Раніше near = частка пікселів РЕЧІ, що
    потрапили в приобличчеву зону. Це хибний знаменник: гольф дав 0.468 і випав із
    правила K-CLR-02 через поріг 0.5, а максі-пальто дало б 0.13 — хоча його комір
    стоїть просто біля обличчя. Велика річ автоматично отримувала малий near.
    Правильний знаменник — саме приобличчеве поле: near = яку його частку ця річ
    займає. Сума по речах = 1. Гольф і комір пальта тепер обидва високі, джинси — 0."""
    c, R = смуга_обличчя(face_mask, радіусів)
    if not c or not поле_смуги: return None
    свої = sum(1 for (x, y) in pixels if math.hypot(x-c[0], y-c[1]) <= R)
    return round(свої/поле_смуги, 3)

# `near_face` → лабораторія/без_викликача.py (Н-02-02: ДОСЯЖНІСТЬ 13.09 — «ніхто»)

def допуск(L, база=6.0):
    """ΔE00-допуск не може бути сталим по світлоті. ВИМІР: однотонний темний светр
    (28,28,30) з фотошумом σ=3 на канал дав L* від 5.8 до 42.4 і два «кольори» з
    ΔE00=7.0 між ними — бо a*/b* виводяться з різниць кубічних коренів і біля нуля
    їхня похідна величезна. Сталий поріг 6 розбиває чорний светр на два кольори,
    а це найчастіший колір реального каталогу. T3."""
    if L < 20: return база*2.5
    if L < 35: return база*1.6
    return база

def кольори(px, pixels, поріг=6.0, мін_частка=0.05, вибірка=3000):
    """Кольори речі З ПІКСЕЛІВ, кожен зі своєю площею. Меланж, твід, деним і
    градієнт перестають бути одним hex: вони дають кілька кольорів із частками.
    Кластер під `мін_частка` — фактура, не колірний елемент образу."""
    # Детерміновано: випадкова вибірка давала різну кількість кольорів для однієї
    # й тієї ж речі у двох станах образу (светр: 2 надворі, 3 у приміщенні).
    pts = sorted(pixels)
    if len(pts) > вибірка: pts = pts[::max(1, len(pts)//вибірка)][:вибірка]
    labs = [to_lab(px[p]) for p in pts]
    кл = []
    for lab in labs:
        for g in кл:
            центр = tuple(v/g["n"] for v in g["сума_lab"])
            if de00(центр, lab) <= допуск(центр[0], поріг):
                g["сума_lab"] = tuple(a+b for a, b in zip(g["сума_lab"], lab)); g["n"] += 1; break
        else:
            кл.append(dict(сума_lab=lab, n=1))
    # Злиття: жадібний прохід порівнює з ПЕРШИМ членом кластера, тому шум фото
    # (σ≈3) розбивав однотонну річ на кілька «кольорів». Тепер кластери, чиї
    # середні ближчі за поріг, зливаються до збіжності.
    змінилось = True
    while змінилось and len(кл) > 1:
        змінилось = False
        for i in range(len(кл)):
            for j in range(i+1, len(кл)):
                a = tuple(v/кл[i]["n"] for v in кл[i]["сума_lab"])
                b = tuple(v/кл[j]["n"] for v in кл[j]["сума_lab"])
                if de00(a, b) <= допуск(min(a[0], b[0]), поріг):
                    кл[i]["сума_lab"] = tuple(x+y for x, y in zip(кл[i]["сума_lab"], кл[j]["сума_lab"]))
                    кл[i]["n"] += кл[j]["n"]; кл.pop(j); змінилось = True; break
            if змінилось: break
    # Центр — медіана по каналах, а не середнє: допуск у темряві широкий, і
    # шумовий хвіст тягнув середнє вниз (чорний светр читався як L*0.9).
    for g in кл: g.setdefault("члени", [])
    for lab in labs:
        best = min(кл, key=lambda g: de00(tuple(v/g["n"] for v in g["сума_lab"]), lab))
        best["члени"].append(lab)
    import statistics as _st
    out = [dict(lab=tuple(round(_st.median(m[i] for m in g["члени"]), 1) for i in range(3))
                     if g["члени"] else tuple(round(v/g["n"], 1) for v in g["сума_lab"]),
                частка=round(g["n"]/len(labs), 3)) for g in кл]
    out.sort(key=lambda d: -d["частка"])
    великі = [c for c in out if c["частка"] >= мін_частка]
    дрібні = [c for c in out if c["частка"] < мін_частка]
    if не_порожньо(дрібні) and великі:
        великі[0]["внутрішній_розкид"] = round(max(
            de00(великі[0]["lab"], c["lab"]) for c in out), 1)
    return великі or out[:1], round(sum(c["частка"] for c in дрібні), 3)

def не_порожньо(x):
    """Чи список непорожній — предикат з іменем, щоб умова читалась словами."""
    return bool(x)

def образ_з_масок(px, masks, порядок, слоти, face_mask=None, знімається=()):
    """Головний вхід шляху A: пікселі + маски -> речі з ВИМІРЯНИМИ площами,
    приобличчевою вагою і власними кольорами. Повертає обидва стани K-WEA-02:
    «надворі» — як є; «у приміщенні» — верхній шар знято і оклюзія перерахована."""
    # `знімається` — ІМЕНА масок верхнього шару, які зникають у приміщенні.
    # Раніше параметр звався `шари` і документувався як слот, а звірявся з іменем маски
    # через мертву функцію _слот, яка завжди повертала ім'я. Тепер контракт один.
    невідомі = [n for n in знімається if n not in masks]
    if невідомі: raise ValueError(f"у masks нема шарів {невідомі}")
    # ШОВ, ЯКИЙ РОЗІЙШОВСЯ НА НАСКРІЗНОМУ ПРОГОНІ: outfit.елементи() читає r["слот"],
    # а цей модуль його не віддавав -> KeyError на стику. Слот не вгадується з імені
    # маски: сегментатор називає їх як завгодно.
    без_слота = [n for n in порядок if n not in слоти]
    if без_слота: raise ValueError(f"не задано слот для {без_слота}: "
                                   "outfit.py адресує правила за слотами")
    стани = {"надворі": list(порядок),
             "у_приміщенні": [n for n in порядок if n not in знімається]}
    рез = {}
    for назва, ord_ in стани.items():
        вид = видимі({k: v for k, v in masks.items() if k in ord_}, ord_)
        поле = sum(len(v) for v in вид.values()) or 1
        c, R = смуга_обличчя(face_mask) if face_mask else (None, None)
        поле_смуги = (sum(1 for p in set().union(*вид.values()) if
                          math.hypot(p[0]-c[0], p[1]-c[1]) <= R)
                      if c and вид else 0)
        речі = []
        for nm in ord_:
            p = вид.get(nm, set())
            if not p: continue
            cols, шум = кольори(px, p)
            речі.append(dict(id=nm, слот=слоти[nm], площа=round(len(p)/поле, 3),
                             джерело_площі="піксель",
                             near=near_share(p, face_mask, поле_смуги) if face_mask else None,
                             colors=[dict(lab=c["lab"], coverage=c["частка"]) for c in cols],
                             дрібний_розкид=шум, пікселів=len(p)))
        рез[назва] = речі
    return рез

