"""Площа елемента образу — ВИМІР, не таблиця.

Чому цей файл існує. У першій версії outfit.py площі бралися зі словника слотів
(верх 22%, низ 30%, взуття 7%). Це таблиця, видана за вимір: довге пальто і кроп-топ
отримували те саме число, максі-спідниця і міні — теж. Оскільки пороги площі
вирішують долю знахідок (бюджет хроми, сирота-акцент, крос-нейтралі), помилка
площі напряму стає хибним вердиктом над реальною річчю.

Два реальні джерела, обидва — обчислення з реальних чисел:

  A. З ПІКСЕЛІВ (головний шлях, коли образ уже є як зображення — фото або рендер
     try-on). Площа = частка видимих пікселів речі після оклюзії шарами.
     Тим самим знімається ще одна діра: колір речі теж береться з пікселів, тож
     меланж/твід/деним дають кілька кольорів зі СВОЇМИ площами, а не один hex.

  B. З ГЕОМЕТРІЇ (шлях до рендеру, на етапі підбору, коли зображення ще нема).
     Площа = фронтальна проєкція виробу на це тіло: вертикальний проміжок виробу
     (з довжини в см) × ширина тіла на цих рівнях × припуск крою. Кроп-топ на
     високій жінці і на petite дають різні числа, бо числа різні.

Якщо жодне джерело недоступне — площа не вигадується. Повертається None, і
правила, що спираються на пороги площі, у outfit.py утримуються (сила ≤ верифікація).
"""
