def _перевірити_проміжок(профіль, верх_см, низ_см):
    """Довжини приходять із розмірної таблиці магазину — а вона буває брудна.
    Проміжок поза тілом раніше тихо обрізався: пальто «висотою 200 см» на зрості 164
    давало правдоподібне число замість помилки інджесту."""
    зріст = профіль[0][1]
    for v in (верх_см, низ_см):
        if not (-1e-6 <= v <= зріст + 1e-6):
            raise ValueError(f"рівень {v:.1f} см поза тілом [0, {зріст:.0f}] — "
                             "перевірити довжину виробу у фіді")

# ── ВИСОКЕ СТЕГНО: ЄДИНИЙ ПОХІДНИЙ ОБХВАТ, І ЙОГО ТРЕБА НАЗИВАТИ ────────────
# Тема-1 §5.1 і §17.3. Високе стегно входить у каскад FFIT рівно двічі, і обидва
# рази це межа Spoon / не-Spoon. Якщо його ВИВОДИТИ часткою від стегна, умова
# `high_hip/waist ≥ 1.193` алгебраїчно згортається в `hip/waist ≥ 1.297` — вісь не
# псується, вона ЗНИКАЄ, і розподіл міток лишається правдоподібним на вигляд.
# Виміряні наслідки: 4.2% тіл дістають іншу мітку; Bottom Hourglass стає
# АЛГЕБРАЇЧНО неможливим при талії нижче ~77 см (потрібні одночасно hip−waist ≥ 22.9
# і hip/waist < 1.297), тобто найбільша категорія в британській і американській
# вибірках зникає для половини обслуговуваного діапазону.
#
# §17.3 називає це не емпіричним твердженням, а алгеброю, і дає силу `hard`:
# «if high hip is not measured, do not emit a label that depends on it. Report the
# input as absent.» Тому 0.92 ЛИШАЄТЬСЯ — але як ПОЗНАЧЕНИЙ фолбек, який ПРИДУШУЄ
# розрізнення, а не підробляє його. Ознака їде в профілі й читається споживачами.
ЧАСТКА_ВИСОКОГО_СТЕГНА = 0.92
ВИСОКЕ_СТЕГНО_ПИТАННЯ = (
    "Обхват високого стегна: %g см (7\") нижче природної талії, по кістці тазу. "
    "Це п'ятий вимір, і він купує рівно одне розрізнення — Spoon проти Bottom "
    "Hourglass, — але воно предметне: Chrimes та ін. 2023 фіксують, що жінки Spoon "
    "додатково скаржаться на тісноту в СТЕГНАХ (thigh), а Bottom Hourglass — ні."
    % ВИСОКЕ_СТЕГНО_ПІД_ТАЛІЄЮ_СМ)

ПОТРІБНІ_ОБХВАТИ = ("плечі", "груди", "талія", "стегна")

def профіль_тіла(зріст_см, обхвати_см):
    """обхвати_см: {'плечі','груди','талія','стегна'} — з картки людини.
    Необов'язковий 'високе_стегно' — якщо він є, вісь Spoon/Bottom-Hourglass жива;
    якщо нема, вона ПРИДУШЕНА (див. блок вище), і це видно в `провенанс_ширин`.

    Ширина фронтальної проєкції ≈ обхват/π (еліпс із помірним сплюсненням).
    Обхват 'плечі' — через середину дельтоподібних м'язів (форма, ANSUR II), і його ширина стоїть на
    вузлі «плечі» — нижній межі його рівня (пахва), а не на лінії плеча (акроміон): висоти середини
    м'яза обмір не дає (рішення 13.11, п.2). Вузлів профілю — `ВУЗЛИ_ПРОФІЛЮ`, лінії плеча серед них нема.
    ВИПРАВЛЕНО ПІСЛЯ ПРОБИ: раніше відсутні обхвати мовчки замінювались числами
    (28/24/30 см), тобто площа рахувалась на вигаданому тілі й виглядала як вимір.
    Тепер відсутній вимір — це помилка, а не дефолт."""
    бракує = [k for k in ПОТРІБНІ_ОБХВАТИ if not обхвати_см.get(k)]
    if бракує:
        raise ValueError(f"нема обхватів {бракує}: площа рахується на реальному тілі, "
                         "інакше вона не вимір. Взяти з картки людини або з мірок бренду")
    if not (120 <= зріст_см <= 210):
        raise ValueError(f"зріст {зріст_см} поза правдоподібним діапазоном")
    w = {k: v/math.pi for k, v in обхвати_см.items()}
    вс_вимір = bool(обхвати_см.get("високе_стегно"))
    вс = (w["високе_стегно"] if вс_вимір
          else w["стегна"] * ЧАСТКА_ВИСОКОГО_СТЕГНА)
    ш = {"маківка": w["плечі"]*0.38, "підборіддя": w["плечі"]*0.38,
         "плечі": w["плечі"], "груди": w["груди"],
         "талія": w["талія"], "високе_стегно": вс,
         "стегна": w["стегна"], "пах": w["стегна"]*0.86,
         "коліно": w["стегна"]*0.42, "литка": w["стегна"]*0.38,
         "щиколотка": w["стегна"]*0.22, "підлога": w["стегна"]*0.26}
    висоти = висоти_рівнів(зріст_см)
    return [(nm, висоти[nm], ш[nm]) for nm in ВУЗЛИ_ПРОФІЛЮ]


def провенанс_високого_стегна(обхвати_см):
    """Чи високе стегно ВИМІРЯНЕ, і що з цього випливає для міток.

    Викликається кожним споживачем, який збирається сказати щось, що залежить від
    цієї осі. Повертає `придушити` — список тверджень, які не мають права
    вийти, поки виміру нема."""
    if обхвати_см.get("високе_стегно"):
        return dict(вимір=True, частка=None, придушити=[],
                    чому="високе стегно виміряне рулеткою — вісь Spoon/Bottom "
                         "Hourglass жива")
    return dict(
        вимір=False, частка=ЧАСТКА_ВИСОКОГО_СТЕГНА,
        придушити=["Spoon", "Bottom Hourglass", "роль зони «високе_стегно»",
                   "будь-яка мітка форми, що спирається на high_hip/waist"],
        чому="високе стегно ВИВЕДЕНЕ як стегна × %.2f, не виміряне. Умова FFIT "
             "`high_hip/waist ≥ 1.193` при цьому згортається в `hip/waist ≥ 1.297`, "
             "тобто вісь не псується, а зникає (тема-1 §17.3, алгебра, сила hard). "
             "Ширини по висоті лишаються придатними — придушено лише мітки, що "
             "стоять НА ЦІЙ ОСІ" % ЧАСТКА_ВИСОКОГО_СТЕГНА,
        як_зняти=ВИСОКЕ_СТЕГНО_ПИТАННЯ)

def площа_виробу(профіль, верх_см, низ_см, припуск=ТИПОВИЙ_КРІЙ, покриття=1.0):
    """Інтеграл ширини тіла по вертикальному проміжку виробу × припуск крою.
    верх_см/низ_см — висота над підлогою, тобто те, що реально дає розмірна
    таблиця магазину (довжина виробу + точка посадки), а не слот.
    (Докстрінг стояв ПІСЛЯ виклику перевірки, тобто не був докстрінгом узагалі.)"""
    _перевірити_проміжок(профіль, верх_см, низ_см)
    k = ПРИПУСК.get(припуск, 1.10); S = 0.0
    for i in range(len(профіль)-1):
        (_, y1, w1), (_, y2, w2) = профіль[i], профіль[i+1]
        lo, hi = min(y1, y2), max(y1, y2)
        a, b = max(min(верх_см, низ_см), lo), min(max(верх_см, низ_см), hi)
        if b <= a: continue
        t1 = (a-lo)/(hi-lo); t2 = (b-lo)/(hi-lo)
        wa = w2 + (w1-w2)*t1; wb = w2 + (w1-w2)*t2
        S += (wa+wb)/2 * (b-a)
    return S * k * покриття

ПРОФІЛІ_БЛИЗЬКОСТІ = {
    # вага внеску площі як функція відстані від краю обличчя, d ∈ [0,1]
    # (0 = впритул до підборіддя, 1 = дальній край приобличчевої смуги)
    "рівномірний":  lambda d: 1.0,
    "лінійний":     lambda d: 1.0 - d,
    "квадратичний": lambda d: (1.0 - d) ** 2,
}


def образ_з_геометрії(профіль, речі, профіль_близькості="рівномірний", кроків=24):
    """речі: [dict(id, верх_см, низ_см, припуск, покриття?)] — числа з розмірної
    таблиці магазину і посадки на цьому зрості. Повертає частки площі образу.

    NEAR — ОДНЕ ВИЗНАЧЕННЯ НА ОБИДВА ШЛЯХИ (виправлено після розбору). Було: частка
    ВИСОТИ САМОЇ РЕЧІ, що потрапила в приобличчеву смугу — тобто рівно той знаменник,
    який near_share() (піксельний шлях) явно називає хибним і від якого відмовився.
    Дві несумісні величини їхали в одне поле `near`, під один поріг NEAR_МІН=0.15 і в
    один множник сили правил метали/температура_нейтралі — числа розходились удвічі.
    Тепер тут те саме, що в near_share: частка приобличчевого ПОЛЯ, яку займає ця річ.

    СУМА: 1.0, КОЛИ ХОЧ ОДНА РІЧ ЗАХОДИТЬ У СМУГУ; 0.0 ДЛЯ ВСІХ, КОЛИ ЖОДНА НЕ ЗАХОДИТЬ.
    Докстрінг раніше казав беззастережно «Сума по речах = 1» — це неправда для образу,
    де все нижче підборіддя на відстані (спідниця + взуття). Споживач, який нормував
    би на цю обіцянку, ділив би на нуль. Поле `near_поле_порожнє` тепер каже про це прямо.

    ПРОФІЛЬ БЛИЗЬКОСТІ (параметр був у виміру, але не в цій функції — `вимір_близькості.py`
    падав із TypeError і НЕ ПРОГАНЯВСЯ ЖОДНОГО РАЗУ). Гіпотеза, яку він мав перевірити:
    рівномірна вага в смузі системно занижує дрібний елемент упритул до лиця. Тепер
    вага внеску площі спадає з відстанню від краю обличчя за одним із ПРОФІЛІ_БЛИЗЬКОСТІ.
    ДЕ ЛАМАЄТЬСЯ: смуга завширшки в одну голову — конвенція, не вимір; профіль спаду
    теж не міряний. Тому дефолт лишається «рівномірний», доки вимір не покаже, що
    інший профіль МІНЯЄ ВЕРДИКТ, а не третій знак після коми."""
    вага = ПРОФІЛІ_БЛИЗЬКОСТІ.get(профіль_близькості)
    if вага is None:
        raise ValueError(f"невідомий профіль близькості {профіль_близькості!r}: "
                         f"є {sorted(ПРОФІЛІ_БЛИЗЬКОСТІ)}")
    S = {r["id"]: площа_виробу(профіль, r["верх_см"], r["низ_см"],
                               r.get("припуск", ТИПОВИЙ_КРІЙ), r.get("покриття", 1.0))
         for r in речі}
    tot = sum(S.values()) or 1.0
    підборіддя = next(y for nm, y, _ in профіль if nm == "підборіддя")
    голова_см = профіль[0][1] - підборіддя
    смуга_низ, смуга_верх = підборіддя - голова_см, підборіддя   # ≈ одна голова від краю обличчя
    S_смуги = {}
    for r in речі:
        a = max(смуга_низ, min(r["верх_см"], r["низ_см"]))
        b = min(смуга_верх, max(r["верх_см"], r["низ_см"]))
        if b <= a:
            S_смуги[r["id"]] = 0.0; continue
        акум = 0.0
        for i in range(кроків):                     # інтеграл площі × вага(відстань)
            y1 = a + (b - a) * i / кроків
            y2 = a + (b - a) * (i + 1) / кроків
            d = (підборіддя - (y1 + y2) / 2) / голова_см if голова_см else 0.0
            акум += площа_виробу(профіль, y1, y2, r.get("припуск", ТИПОВИЙ_КРІЙ),
                                 r.get("покриття", 1.0)) * вага(max(0.0, min(1.0, d)))
        S_смуги[r["id"]] = акум
    сума_смуги = sum(S_смуги.values())
    поле_смуги = сума_смуги or 1.0
    out = []
    for r in речі:
        out.append(dict(id=r["id"], площа=round(S[r["id"]]/tot, 3), джерело_площі="геометрія",
                        near=round(S_смуги[r["id"]]/поле_смуги, 3),
                        near_визначення="частка приобличчевого поля (як у near_share)",
                        near_профіль=профіль_близькості,
                        near_поле_порожнє=(сума_смуги == 0.0),
                        см2=round(S[r["id"]])))
    return out

