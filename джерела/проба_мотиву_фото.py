"""ПРОБА МОТИВУ З ФОТО — старий і новий рядок «візерунок» у промптах збагачення.

НАВІЩО (18.09.2026). На каталог_збагачення.json.gz (10 770 описів qwen3-vl-8b) поле
`візерунок` ні разу не сказало «анімалістичний», хоч слово в дозволених: у 41 речі
власний «опис» моделі каже «леопардовий/зебровий принт», «зміїна шкіра», а поле —
квітковий 25, принт 9, смужка 6. Горох теж ішов у «квітковий». Підозра — рядок
промпту «однотонний, смужка, клітинка, горох, квітковий тощо» і «чи є смуги/клітинка/
квіти» в описі: приклад без тварини й без крапок тягне модель до квітів.

Вибірка — зі старого запису (сім'я за власним описом моделі, V.клас_мотиву):
всі анімалістичні, до 12 «крапок/гороху», по 15 випадкових квіткових і однотонних.
Кожне фото йде через старий і новий промпт v1 (жнива_збагачення.ПРОМПТ) і, для
одягу, через старий і новий ПРОМПТ_ОДЯГ/ДРІБНЕ жнива_v2. Старі промпти беруться з
`git show <реф>:джерела/…` — тобто саме те, що стоїть у main.

Запуск (з джерела/, LM Studio з qwen3-vl-8b на 127.0.0.1:1234):
    python проба_мотиву_фото.py [--реф origin/main] [--потоки 3] [--вихід шлях.json]
"""
import argparse, gzip, json, os, random, re, subprocess, sys, types, urllib.request
from concurrent.futures import ThreadPoolExecutor

import verify as V
import жнива_збагачення as Н1
import жнива_v2 as Н2

ТУТ = os.path.dirname(os.path.abspath(__file__))
КРАПКИ = re.compile(r"крап|горох|горош|polka", re.I)
# тип_запиту v1 → слот v2 (v2 бере слот із feed.слот; тут запису офера нема)
СЛОТ_ТИПУ = dict(**{т: "верх" for т in ("блуза", "футболка", "топ", "светр", "лонгслів", "сорочка", "боді", "жилет", "худі", "світшот")},
                 **{т: "верхній_шар" for т in ("жакет", "пальто", "куртка", "кардиган", "піджак", "тренч", "плащ")},
                 **{т: "низ" for т in ("штани", "спідниця", "джинси", "шорти")},
                 сукня="сукня", костюм="сукня")
ВІЗЕРУНОК_В_ОПИСІ = re.compile(r"смуг|клітин|квіт|крап|горох|принт|візерун|леопард|зебр|зміїн|тигр|орнамент|малюн|геометр|абстракт|мереж|вишив", re.I)


def старий_модуль(реф, файл):
    код = subprocess.run(["git", "show", "%s:джерела/%s" % (реф, файл)], cwd=ТУТ,
                         capture_output=True, check=True).stdout.decode("utf-8")
    м = types.ModuleType(файл[:-3] + "_старий")
    м.__file__ = os.path.join(ТУТ, файл)
    exec(compile(код, файл, "exec"), м.__dict__)
    return м


def вибірка(дані, сід=18):
    р = random.Random(сід)
    сім = lambda з: V.клас_мотиву(з.get("опис") or "")["клас"]
    ані = [(к, з, "анімалістичний") for к, з in дані.items() if сім(з) == "анімалістичний"]
    кр = [(к, з, "горох") for к, з in дані.items() if КРАПКИ.search(з.get("опис") or "")
          and сім(з) != "анімалістичний"]
    кв = [(к, з, "квітковий") for к, з in дані.items()
          if з.get("візерунок") == "квітковий" and сім(з) == "квітковий"]
    од = [(к, з, "однотонний") for к, з in дані.items()
          if з.get("візерунок") == "однотонний" and not ВІЗЕРУНОК_В_ОПИСІ.search(з.get("опис") or "")]
    р.shuffle(кр); р.shuffle(кв); р.shuffle(од)
    return ані + кр[:12] + кв[:15] + од[:15]


def v1(мод, b64, тип):
    return мод.спитати("qwen3-vl-8b-instruct", b64, тип)[0]


def v2(мод, b64, тип, слот):
    набір = мод.набір_слота(слот)
    if набір not in ("одяг", "дрібне"):
        return None
    тіло = {"model": "qwen3-vl-8b-instruct", "temperature": 0, "max_tokens": 600,
            "messages": [{"role": "user", "content": [
                {"type": "text", "text": мод._підставити(мод.ПРОМПТ_НАБОРУ[набір], тип)},
                {"type": "image_url", "image_url": {"url": "data:image/jpeg;base64," + b64}}]}]}
    for спроба in range(3):
        try:
            зап = urllib.request.Request(мод.СЕРВЕР, data=json.dumps(тіло).encode("utf-8"),
                                         headers={"Content-Type": "application/json"})
            with urllib.request.urlopen(зап, timeout=180) as в:
                текст = json.load(в)["choices"][0]["message"]["content"]
            return мод.нормалізувати(json.loads(re.search(r"\{.*\}", текст, re.S).group(0)), набір)
        except Exception:
            if спроба == 2:
                raise


def main():
    ап = argparse.ArgumentParser()
    ап.add_argument("--реф", default="origin/main")
    ап.add_argument("--потоки", type=int, default=3)
    ап.add_argument("--вихід", default=None)
    а = ап.parse_args()
    с1, с2 = старий_модуль(а.реф, "жнива_збагачення.py"), старий_модуль(а.реф, "жнива_v2.py")
    дані = json.load(gzip.open(os.path.join(ТУТ, "каталог_збагачення.json.gz"), "rt", encoding="utf-8"))
    ряди = вибірка(дані)
    print("вибірка:", len(ряди), {с: sum(1 for р in ряди if р[2] == с) for с in
                                   ("анімалістичний", "горох", "квітковий", "однотонний")}, flush=True)

    def одна(р):
        к, з, правда = р
        тип = з.get("тип_запиту") or "річ"
        вих = dict(id=к, правда=правда, тип=тип, опис_запису=з.get("опис"), поле_запису=з.get("візерунок"))
        try:
            b64 = Н1.стиснути(Н1._качати(з["фото"]))
        except Exception as e:
            вих["помилка"] = "фото: %s" % e
            return вих
        слот = СЛОТ_ТИПУ.get(тип, тип)
        for назва, f in (("v1_старий", lambda: v1(с1, b64, тип)), ("v1_новий", lambda: v1(Н1, b64, тип)),
                         ("v2_старий", lambda: v2(с2, b64, тип, слот)), ("v2_новий", lambda: v2(Н2, b64, тип, слот))):
            try:
                о = f()
                вих[назва] = None if о is None else dict(візерунок=о.get("візерунок"), опис=о.get("опис"))
            except Exception as e:
                вих[назва] = dict(помилка=str(e)[:120])
        print("%-15s %-10s v1 %s→%s  v2 %s→%s" % (правда, тип,
              *[(вих.get(н) or {}).get("візерунок") for н in ("v1_старий", "v1_новий", "v2_старий", "v2_новий")]), flush=True)
        return вих

    with ThreadPoolExecutor(а.потоки) as пул:
        рез = list(пул.map(одна, ряди))
    if а.вихід:
        json.dump(рез, open(а.вихід, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    print("\nполе «візерунок» = сім'я за описом старого запису (збіг / усі з відповіддю)")
    for правда in ("анімалістичний", "горох", "квітковий", "однотонний"):
        рр = [р for р in рез if р["правда"] == правда and "помилка" not in р]
        ряд = []
        for н in ("v1_старий", "v1_новий", "v2_старий", "v2_новий"):
            є = [р[н]["візерунок"] for р in рр if р.get(н) and "помилка" not in р[н]]
            ряд.append("%s %2d/%-2d" % (н, sum(1 for x in є if x == правда), len(є)))
        print("%-15s %s" % (правда, "   ".join(ряд)))
    for н in ("v1_старий", "v1_новий"):
        c = {}
        for р in рез:
            x = (р.get(н) or {}).get("візерунок", "—")
            c.setdefault(р["правда"], {}).setdefault(x, 0)
            c[р["правда"]][x] += 1
        print(н, json.dumps(c, ensure_ascii=False))


if __name__ == "__main__":
    main()
