    обр = []
    for i, о in enumerate(образи or [], 1):
        if not isinstance(о, dict) or "речі_н" not in о:
            continue
        блокери = list(о.get("блокери") or [])
        зап = dict(ід=str(о.get("номер") or ("о%d" % i)), речі=list(о["речі_н"]))
