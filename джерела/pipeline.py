"""НАСКРІЗНИЙ ВХІД. Один шов між кодом і ші-стилістом, у два боки.

ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after):
  before — у кожного модуля свій `__main__`-демо, а ланцюжка «особа + фід + нагода →
           що показати стилістові → перевірити, що він обрав» не проганяло ніщо.
           Викликач мусив сам знати, що спершу треба контраст_особи, тоді сценарій,
           тоді розвилка, тоді запит_у_фід, тоді покриття — і сам зшивати п'ять
           виходів. Через це `для_стиліста`, `перевірити_контракт` і
           `розвилка_специфікацій` роками лишались без жодного виклику.
  after  — два виклики: `підготувати(...)` віддає ПАКЕТ, `перевірити_образ(...)`
           приймає обраний образ і віддає знахідки в контракті виходу.

ХТО ОБИРАЄ РЕЧІ. Не цей файл. Вибір речей — робота ші-стиліста: він читає пакет
(де вже є реальні SKU під кожне вікно, ціль сценарію, вето, розвилка палітр із
родоводом і чесні обмеження) і складає образ. Код не ранжує й не зводить у бал —
він МІРЯЄ і віддає простір вибору. Тому тут нема жодної евристики підбору: спроба
її написати була б поверненням до вироку, від якого архітектура свідомо відмовилась.

ЩО ПАКЕТ ГАРАНТУЄ СТИЛІСТОВІ:
  · кожне вікно вже звірене з реальним каталогом — видно, де НУЛЬ SKU, і наскільки
    не дотягує найближча річ (розширити вікно проти відмовитись від схеми);
  · кожна гілка палітри несе родовід і мітку однородовідності — щоб «багато джерел»
    не читалось як незалежне підтвердження;
  · кожне обмеження системи названо (status.py) — стиліст бачить, чого числа НЕ знають.
"""
