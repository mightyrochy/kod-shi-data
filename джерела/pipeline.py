# ── ЧИ ВЦІЛІВ АКЦЕНТ, ЯКОГО ЗАЖАДАВ САМ КОД ────────────────────────────────
# ЩО ЦЕ ЛОВИТЬ (правило 3, реальний випадок 04.09.2026). Тестувальниця обрала
# червоний і схему «нейтрали+акцент». Спека поклала акцент на взуття й сумку
# (C 28–70, L 57–72). Обидві руки віддали суцільно чорний образ — C ≈ 2 на всіх
# чотирьох слотах. Суддя видав 8 знахідок і ЖОДНОЇ про колір: код приписав
# слоту роль і не перевірив, чи вона виконана. Петля була розімкнена — приписав
# і забув. Мовчання судді неможливо відрізнити від «акцент на місці».
#
# СИЛА ≤ ВЕРИФІКАЦІЯ (правило 4). Тут не стверджується, що образ гірший, — це
# скаже носій. Стверджується рівно те, що вимірюється: код зажадав хрому в
# слоті, річ у слоті її не має. Тому дві РІЗНІ знахідки, бо це два різні
# дефекти з різними адресатами:
#   · пул мав чим — це вибір проти власної спеки (адресат: промпт і модель);
#   · пул не мав чим — це дефіцит каталогу (адресат: закупівля джерел), і
#     звинувачувати модель тут було б помилкою атрибуції.
def акцент_образу(речі, спец_слоти, кандидати=None, за_ід=None):
    """[знахідки] — де роль «акцент» призначена, але хроми в образі нема.

    `за_ід` — id → запис КАТАЛОГУ. Він тут обов'язковий: записи пулу, які їдуть
    до моделі, несуть лише назву, ціну й словесну зону, БЕЗ `lab`. Рахувати
    хрому по них означало б діставати None на кожній речі й через це завжди
    списувати провал на каталог — тобто зробити звинувачення сталим, а перевірку
    невідрізненною від заглушки. Спіймано першим же прогоном: «у пулі НЕМА
    жодної речі з хромою» стояло і там, де речі були.
    """
    if not спец_слоти:
        return []
    за_слотом = {}
    for r in речі:
        за_слотом.setdefault(r.get("слот"), r)
    зн = []
    # ключі на «_» — службові (напр. `_схема`), не слоти. Без цього фільтра
    # рядок схеми потрапляв у цикл як «слот» і валив перевірку AttributeError.
    акцентні = [(с, сп) for с, сп in спец_слоти.items()
                if not str(с).startswith("_") and isinstance(сп, dict)
                and сп.get("роль") == "акцент" and сп.get("C")]
    for с, сп in акцентні:
        r = за_слотом.get(с)
        if r is None:                      # слота в образі нема — це не «зник акцент»
            continue
        C = _хрома(r)
        if C is None:                      # колір речі не виміряний: мовчати чесніше,
            continue                       # ніж рахувати невимір за провал
        Cmin = float(сп["C"][0])
        if C >= Cmin:
            continue
        # чи взагалі БУЛО з чого взяти акцент у цьому слоті
        пул = ((кандидати or {}).get(с) or [])
        повні = [(за_ід or {}).get(x.get("id")) or x for x in пул]
        мали = [x for x in повні if (_хрома(x) or 0.0) >= Cmin]
        if мали:
            зн.append(dict(правило="K-PAL-18", сила="soft", бік="код",
                           слот=с, ярлик="акцент зник",
                           суть=("схема «%s» дала слоту «%s» роль акценту (хрома від %.0f), "
                                 "а річ у ньому має %.0f — у пулі було %d речей із хромою"
                                 % (спец_слоти.get("_схема", "?"), с, Cmin, C, len(мали))),
                           чому="вибір проти власної спеки: акцент був доступний і не взятий",
                           що_зняло_б="річ із хромою ≥ %.0f у слоті «%s»" % (Cmin, с)))
        else:
            зн.append(dict(правило="K-PAL-18", сила="hint", бік="дані",
                           слот=с, ярлик="акценту не було з чого взяти",
                           суть=("схема «%s» вимагає акценту в слоті «%s» (хрома від %.0f), "
                                 "але в пулі цього слота НЕМА жодної речі з такою хромою"
                                 % (спец_слоти.get("_схема", "?"), с, Cmin)),
                           чому="дефіцит каталогу, не вибір моделі: звинувачувати модель тут — "
                                "помилка атрибуції",
                           що_зняло_б="джерела з кольоровими речами в цьому слоті"))
    # ЗВЕДЕНОЇ ЗНАХІДКИ («жоден акцентний слот не несе хроми») ТУТ НЕМА НАВМИСНО.
    # Вона була написана й ВИДАЛЕНА того ж прогону: `слот=None` не чіпляється до
    # жодної речі, тому граф її відкидає, і назовні їхали дві знахідки з трьох.
    # Правило, яке виконується, лишає слід і не доходить до людини, — рівно той
    # третій ярус, який тут заборонено. Дві послотові знахідки кажуть усе те саме
    # й доїжджають.
    return зн


def _хрома(r):
    """C* речі або None. None — це «не виміряно», і воно не рахується за провал."""
    lab = r.get("lab")
    if not lab and r.get("hex"):
        try:
            import colorspace as _КС
            lab = _КС.hx(r["hex"])
        except Exception:
            lab = None
    if not lab or len(lab) < 3:
        return None
    return (float(lab[1]) ** 2 + float(lab[2]) ** 2) ** 0.5


def структура_образу(речі, слоти_пулу=None):
    """Блокери означення образу: по одній речі на слот, і є сукня або верх+низ.

    Це не правило стилю — це те, чим образ є. Дві пари взуття в одному образі
    ніхто не носить; образ без верху й низу (і без сукні) — це не образ, а
    аксесуари. Верхній шар, взуття, сумка й прикраси можуть бути відсутні —
    їх відсутність не робить образ не-образом.

    `слоти_пулу`: id → множина слотів, у яких ця річ стояла в пулі. ДВОСЛОТОВІ
    речі (кардиган: каталожний слот «верхній_шар», а в пулі і «верх») мусять
    рахуватись тим слотом, у якому вони справді стоять в образі: без цього
    кардиган, узятий як верх, дав би хибний блокер «нема верх» (спіймано
    пробою 02.09). Правило: спершу кожна річ бере свій каталожний слот; коли
    обов'язковий слот лишається порожнім, його закриває річ, що мала його в
    пулі, — і тоді вона вже не рахується у своєму каталожному."""
    import collections as _c, composer as _КМ, graph as _ГР
    б = []
    обов = [s for s in _ГР.СЛОТИ if s not in _КМ.СЛОТИ_НЕОБОВЯЗКОВІ]
    # ключ — ПОЗИЦІЯ речі, не id: речі без id (тести, вигадані руками 3/4) не
    # мають злипатись в одну
    призн = [(r.get("слот") or "?") for r in речі]
    # ЦІЛА РІЧ НЕ ПЕРЕПРИЗНАЧАЄТЬСЯ В ПОЛОВИНУ (04.09.2026, спіймано наскрізним
    # прогоном): комплект має в пулі і «верх», і «низ» (слоти_альт), і цикл нижче
    # ставив його у порожній «верх» — після чого «низ» лишався порожнім, і суддя
    # блокував «нема низу» рівно той образ, у якому низ є. Сукня й комплект
    # закривають обидва обов'язкові слоти собою і в перепризначення не входять.
    ЦІЛІ = ("сукня", "комплект")
    if слоти_пулу:
        зайняті = set(призн)
        # (внутрішньої перевірки «річ у ЦІЛІ — пропустити» тут нема навмисно: зовнішня
        # умова вже не пускає в перепризначення жоден образ із цілою річчю, і мутант
        # показав, що внутрішня була мертвою — прибрано того ж дня)
        if not (set(призн) & set(ЦІЛІ)):
            for s in обов:
                if s in зайняті:
                    continue
                for i, r in enumerate(речі):
                    if s in (слоти_пулу.get(str(r.get("id"))) or ()) and призн[i] != s:
                        призн[i] = s; зайняті.add(s); break
    # ДРУГИЙ ШАР НА ТОРСІ (тема-11, 05.09.2026): жакет, кардиган, жилет, піджак, блейзер,
    # болеро, кімоно, накидка поверх верху — це шар, а не другий «верх». Виміряно на
    # чотирьох сценаріях: «у слоті «верх» 2 речі (Базовий жакет…)» блокував законні образи.
    _ШАР2 = re.compile(r"жакет|кардиган|жилет|піджак|блейзер|болеро|кімоно|накидк|пончо|тренч|бомбер", re.I)
    if призн.count("верх") > 1:
        _верхи = [i for i, p in enumerate(призн) if p == "верх"]
        _шари = [i for i in _верхи if _ШАР2.search(str(речі[i].get("тип") or "") + " " + str(речі[i].get("назва") or ""))]
        if _шари and len(_шари) < len(_верхи):
            for i in _шари[:1]:
                призн[i] = "шар2"; речі[i]["шар"] = 2
    лічба = _c.Counter(призн)
    for сл, n in лічба.items():
        if n > 1:
            імена = [str(r.get("назва") or r.get("id"))[:40] for i, r in enumerate(речі) if призн[i] == сл]
            б.append("у слоті «%s» %d речі (%s) — образ носять по одній на слот: лиши одну" % (сл, n, "; ".join(імена)))
    є = set(лічба)
    # ОДНЕ ДЖЕРЕЛО ІСТИНИ: обов'язкові слоти — ті, яких композитор не вважає
    # необов'язковими (зараз верх і низ); сукня заміняє обидва. Те саме правило,
    # що стоїть на ПОДАЧІ кандидатів, тепер стоїть і на СУДЖЕННІ образу моделі —
    # доти воно жило лише в композиторі, і образ із самих аксесуарів проходив.
    бракує = [s for s in обов if s not in є]
    if бракує and not ({"сукня", "комплект"} & є):
        б.append("нема %s (і нема сукні, яка їх заміняє) — це аксесуари, а не образ"
                 % " і ".join("«%s»" % s for s in бракує))
    # ── ПОДВОЄНИЙ НИЗ (04.09.2026, рішення власника про комплекти) ───────────
    # Слот «сукня» закриває верх і низ разом — і для сукні, і для костюма/комплекту
    # (feed.набір_цілий). Сукня + спідниця або костюм + штани — два низи, і це
    # не образ, а помилка означення: те саме, що два взуття. Верх ПОВЕРХ сукні
    # (сорочка під сарафан) — законний шар, тому «сукня + верх» тут не блокується.
    if "сукня" in є and "низ" in є:
        б.append("«сукня» і «низ» разом — низ подвоєний: лиши сукню або лиши низ")
    if "комплект" in є and ("низ" in є or "верх" in є):
        б.append("«комплект» (верх і низ в одному SKU) і окремий %s разом — подвоєння: "
                 "лиши комплект або візьми половину, сказавши СВІДОМО"
                 % " та ".join(s for s in ("верх", "низ") if s in є))
    return б


