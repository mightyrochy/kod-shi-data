# ЩО ЦЕ МІНЯЄ НАД РЕАЛЬНОЮ РІЧЧЮ. Кількість речей, які модель БАЧИТЬ при тому
# самому бюджеті символів. Зміряно на каталог_повний (1 215 речей, 154 354 симв
# блоків): заголовки груп дають −26.1 %, індекс замість id ще −11 %, разом
# 96 362 симв — тобто повний пул чотирьох слотів влазить під бюджет 120 000 БЕЗ
# жодного зрізу, тоді як плоский рядок туди клав 945 речей із 1 215.
#
# ЧОМУ ЗАГОЛОВКИ, А НЕ КОРОТШИЙ РЯДОК. Скоротити рядок — разовий виграш сталої
# величини. Повторюване (тип, тканина, смуга світлоти) росте ЛІНІЙНО з каталогом,
# а кількість різних значень — ні: на 1 215 речах виходить 399 груп. На каталозі
# у сто тисяч речей груп буде ті самі кілька тисяч.
#
# ЧОМУ СЛОВНИК КОДІВ ВІДХИЛЕНО. Зміряно: −31.8 % проти −26.1 % у заголовків, тобто
# +5.7 в. п. ціною рядків виду «#412 T7 З12 3550», які модель мусить розшифровувати
# через легенду. Читабельність тут не зручність, а точність вибору.
#
# ЧОМУ ІНДЕКС БЕЗПЕЧНИЙ, ХОЧ ПРИБИРАЄ НАДЛИШКОВІСТЬ. Довгий id самоперевірний:
# вигадане «ж-99999@gepur.com» просто не резолвиться. Голий «#413» замість «#412»
# резолвився б у реальну, але ІНШУ річ — мовчки. Тому номер іде в парі з кодом
# магазину (#412·29), а номери роздаються ПО ЧЕРЗІ між магазинами методом
# найбільшого залишку: сусідні номери майже завжди з різних магазинів, і код
# ловить розбіжність. Зміряно на 1 215 речах: при роздачі підряд сусідні пари з
# одного магазину — 97.3 % (вилов помилки ±1 = 2.7 %); по черзі — 7.5 %
# (вилов 92.5 %), і весь залишок був суцільним хвостом найбільшого магазину в
# кінці діапазону. Пропорційна роздача цей хвіст усуває.
#
# ЧОГО НЕ ЗМІРЯНО: чи модель узагалі частіше помиляється з «#412», ніж із повним
# id. Уся арифметика вилову — страховка від помилки, частоти якої ніхто не бачив;
# `ПАКУВАТИ_ІНДЕКСОМ` існує саме щоб це можна було порівняти прогоном, а не
