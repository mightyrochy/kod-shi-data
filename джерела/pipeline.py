def _доповнення_судді(речі, сценарій=None, драп=None):
    """Правила бази, які базовий суддя не бачить без полів каталогу — за назвою речі.
    K-KOH-10 одна відкрита зона; K-COL-10 змішування принтів; K-CRA-07 один метал;
    K-KOH-06 блиск удень; K-KOH-08 сумка нижче рівня події."""
    сц = сценарій or {}; вих = []
    година = сц.get("година"); вечір = (година is not None and int(година) >= 17)
    _о = сц.get("_ошатність"); lo = None
    if isinstance(_о, (list, tuple)) and len(_о) == 2:
        try: lo = min(float(_о[0]), float(_о[1]))
        except (TypeError, ValueError): lo = None
    def _з(правило, сила, сила_нп, суть, ids):
        return dict(правило=правило, сила=сила, сила_нп=сила_нп, суть=суть + " [з назви речі]", речі=ids,
                    сила_нп_джерело="назва речі (полів каталогу нема)")
    назви = [(r.get("id"), str(r.get("назва") or ""), r.get("слот") or "") for r in речі]
    # 1) K-KOH-10: відкриті зони — декольте/спина, ноги, плечі — по одній зоні на річ
    зони = {}
    for id_, n, сл in назви:
        if сл in ("верх", "сукня", "комплект", "низ"):
            if re.search(r"декольте|корсет|бюстьє|бандо|глибок\w* виріз|відкрит\w* спин|з відкритою спиною", n, re.I): зони.setdefault("декольте/спина", []).append(id_)
            if сл != "верх" and re.search(r"\bміні\b|шорт|коротк\w* спідниц|ультракоротк", n, re.I): зони.setdefault("ноги", []).append(id_)
            if re.search(r"без рукав|на тонких бретел|на бретел|майка|топ-бандо|відкрит\w* плеч", n, re.I): зони.setdefault("плечі", []).append(id_)
    ліміт = 2 if вечір else 1
    if len(зони) > ліміт:
        вих.append(_з("K-KOH-10", "soft", round(min(1.0, (len(зони) - ліміт) / 2.0 + 0.3), 2),
                      "відкритих зон %d (%s) при межі %d для %s" % (len(зони), ", ".join(зони), ліміт, "вечора" if вечір else "дня"),
                      sorted({i for v in зони.values() for i in v})))
    # 2) K-COL-10: два різні принти
    # ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026)
    #   before: · два різні принти в одному образі: анімалістичний, смужка [з назви речі] [0.50]
    #   after:  · різні принти: анімалістичний (верх) + смужка (низ) — зв'язати спільним
    #             кольором або дати одному домінувати площею [з назви речі] [0.50]
    # Старий рядок називав ІМЕНА принтів і не називав ні речі, ні ходу: ші діставала
    # «їх два» без адреси, до якої прикласти руки. Ід у полі `речі` цього не рятують —
    # `промпт_ремонту` друкує лише `суть` і `сила_нп`, а `ремонт` тут не заповнюється
    # взагалі. Слот кожного принта вже лежить у `назви` третім полем, тож речення тепер
    # каже, В ЯКИХ СЛОТАХ принти зіткнулись і що з ними зробити.
    # ХІД НЕ ВИГАДАНО, А ВЗЯТО В САМОГО ПРАВИЛА (ревізія 08.09.2026). Перша редакція
    # хвоста казала «звести до одного принта, решту речей однотонними» — це ЧУЖА, суворіша
    # норма, якої корпус не тримає. Своє ж K-COL-10 (`outfit.принти`) має рівно два виходи
    # у полі `ремонт`: «замінити один принт на версію, що містить колір другого, АБО
    # зв'язати третьою річчю у спільному кольорі», а `ламається` додає третій — «чітке
    # домінування одного принту за площею рятує навіть без нитки» (те саме в
    # звірка_механізмів.md: нитка + різні масштаби + домінування). Мікс принтів корпус НЕ
    # забороняє, тож і речення його не забороняє: воно називає ті самі два виходи.
    ПРИНТИ = [("анімалістичний", r"леопард|зебр|анімал|пітон|змії"), ("смужка", r"смуж|смугаст|stripe"), ("клітинка", r"клітин|карт\w*|тартан|гусяч"), ("квіти", r"квіт|флор"), ("горох", r"горох|горошок|polka")]
    знайдені = {}; слоти_принта = {}
    for id_, n, сл in назви:
        for ім, рег in ПРИНТИ:
            if re.search(рег, n, re.I):
                знайдені.setdefault(ім, []).append(id_)
                слоти_принта.setdefault(ім, []).append(сл or "без слота")
    if len(знайдені) >= 2:
        _де = " + ".join("%s (%s)" % (ім, "/".join(dict.fromkeys(слоти_принта[ім]))) for ім in знайдені)
        вих.append(_з("K-COL-10", "soft", 0.5, "різні принти: %s — зв'язати спільним кольором або дати одному домінувати площею" % _де, sorted({i for v in знайдені.values() for i in v})))
    # 3) K-CRA-07: метал прикрас проти слова людини
    м = str((драп or {}).get("метал") or "").lower()
    теплий = м in ("теплі", "теплий", "золото")
    холодний = м in ("холодні", "холодний", "срібло")
    for id_, n, сл in назви:
        if сл in ("сережки", "намисто", "кольє", "браслет", "каблучка", "брошка", "прикраси", "пояс", "сумка"):
            if теплий and re.search(r"сріб|silver|родій|платин|сталь", n, re.I):
                вих.append(_з("K-CRA-07", "soft", 0.5, "срібний метал при теплій драпіровці (її слово — золото)", [id_]))
            if холодний and re.search(r"золот|gold|позолот|латун", n, re.I):
                вих.append(_з("K-CRA-07", "soft", 0.5, "золотий метал при холодній драпіровці (її слово — срібло)", [id_]))
    # 4) K-KOH-06: блиск удень
    # ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026)
    #   before: · блиск (паєтки/люрекс/стрази) о 13:00 — денний контекст [з назви речі] [0.45]
    #   after:  · блиск (паєтки/люрекс/стрази) у слоті «верх» о 13:00 — денний контекст:
    #             взяти матову річ у цей слот [з назви речі] [0.45]
    # Старий рядок виходив однаковий на паєтковий топ і на люрексову сукню: він називав
    # ГОДИНУ, а не річ, і не мав ходу — «денний контекст» не каже, що з блиском робити,
    # а ід речі в промпт ремонту не друкується. Слот блискучої речі розпакований тут же
    # (`сл` у цьому ж циклі), напрям однобічний — день просить матового; обидва в реченні.
    if година is not None and int(година) < 17:
        for id_, n, сл in назви:
            if re.search(r"паєтк|люрекс|металік|блискіт|стрази|ламе\b", n, re.I):
                вих.append(_з("K-KOH-06", "soft", 0.45, "блиск (паєтки/люрекс/стрази) у слоті «%s» о %02d:00 — денний контекст: взяти матову річ у цей слот" % (сл or "без слота", int(година)), [id_])); break
    # 5) K-KOH-08: сумка нижче рівня події
    if lo is not None and lo >= 6:
        for id_, n, сл in назви:
            if сл == "сумка" and re.search(r"рюкзак|шопер|пляжн|поясн|спортивн|бананк", n, re.I):
                вих.append(_з("K-KOH-08", "soft", 0.6, "тип сумки (рюкзак/шопер/поясна) нижчий за рівень події %d" % int(lo), [id_])); break
    return вих
