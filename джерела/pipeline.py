def вердикт_у_ребра(вердикт, в, коментар=""):
    """Записи для калібрування: на кожне правило образу — його напруга й вердикт."""
    г = в.get("граф") or {}
    з = str(вердикт).strip().lower()
    # ── СЛОВА ПОКАЗУ СТОЯТЬ ТУТ, А НЕ В JS (Н-P12) ───────────────────────────
    # Крок 5 не кликався нізвідки, і розходження словників було невидиме: картка
    # питає «Вдягнеш?» і дає рівно три відповіді — «вдягну як є», «вдягну, якщо
    # змінити одну річ», «не вдягну». Жодна не збігалась із набором нижче, тож
    # КОЖЕН вердикт показу прочитався б як «не носитиму», і калібрування виміряло
    # б власний переклад замість людини. Перекладати в JS не можна з тієї ж
    # причини, з якої формат промпта будує код: два словники розійшлися б на
    # першій правці картки.
    # «ЯКЩО ЗМІНИТИ ОДНУ РІЧ» — НЕ НОСИТИМУ, І ЦЕ НЕ ДРІБНИЦЯ: ребра рахуються
    # проти ЦЬОГО складу образу, а та відповідь каже, що цього складу жінка не
    # вдягне. Третій стан (умовна згода) тут не зникає — він лишається в рядку
    # журналу полем `вердикт_людини`; у калібрування він іде як «ні».
    носитиму = з in ("так", "носитиму", "yes", "1", "true", "вдягну як є")
    ребра = г.get("ребра") if isinstance(г, dict) else None
    if not ребра:
        ребра = [dict(правило=z.get("правило"), напруга=float(z.get("сила_нп") or 0.0))
                 for z in (в.get("знахідки") or []) if z.get("правило")]
    образ = "+".join(str(r.get("id")) for r in (в.get("речі") or в.get("образ") or []))
    return [dict(образ=образ, правило=р["правило"], напруга=round(float(р.get("напруга") or 0.0), 3),
                 носитиму=носитиму, коментар=коментар) for р in ребра]


def калібрування(записи, мінімум=8):
    """Per правило: частка «ні» при присутності ребра проти частки «ні» без нього.
    Це і є «сила ≤ верифікація» в дії: правило з ≥ `мінімум` вердиктів дістає
    вимірний тір (T1), решта — «не калібровано». Різниця часток — розрізнювальна
    сила за вердиктами, НЕ нова константа: вона перераховується з кожним вердиктом."""
    import collections as _c
    за_образом = _c.defaultdict(list)
    for з in записи: за_образом[з.get("образ") or id(з)].append(з)
    усі_образи = list(за_образом.values())
    n_ні_усього = sum(1 for о in усі_образи if о and not о[0]["носитиму"])
    вих = {}
    правила = {з["правило"] for з in записи}
    for р in sorted(правила):
        з_ним = [о for о in усі_образи if any(з["правило"] == р for з in о)]
        без = [о for о in усі_образи if not any(з["правило"] == р for з in о)]
        ні_з = sum(1 for о in з_ним if not о[0]["носитиму"]); ні_без = sum(1 for о in без if not о[0]["носитиму"])
        n = len(з_ним)
        вих[р] = dict(образів_з=n, образів_без=len(без),
                      частка_ні_з=round(ні_з / n, 2) if n else None,
                      частка_ні_без=round(ні_без / len(без), 2) if без else None,
                      різниця=(round(ні_з / n - (ні_без / len(без) if без else 0), 2) if n else None),
                      тір=("T1 (вердикти носіння)" if n >= мінімум else "не калібровано: %d із %d вердиктів" % (n, мінімум)))
    return вих



