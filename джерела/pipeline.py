    # «останнім рядком дай ОБРАЗ:» коротенький і переживає сусідство з чим
    # завгодно. Замовлення на N образів — це п'ять рядків із жорсткою формою, і
    # між ними та відповіддю моделі лежало б півтори сотні рядків каталогу:
    # інструкцію, прочитану до товарного списку, модель виконує гірше за ту, що
