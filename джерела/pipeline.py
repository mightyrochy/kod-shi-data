    _жн = (сценарій or {}).get("_жорстке_ні"); _вт = (сценарій or {}).get("_вето")
    сценарій = {k: v for k, v in (сценарій or {}).items() if k not in ("_жорстке_ні", "_вето")}
    блокує, сума, зн, _повний = _КМ._оцінити(F, речі, тіло, _жн, _вт, **сценарій)
    # ── КЛЮЧ СОРТУВАННЯ І ТЕ, ЩО БАЧИТЬ ЛЮДИНА, — РІЗНІ СПИСКИ (07.09.2026) ────
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after).
    #   before — `_оцінити` СВІДОМО не бере в `зн` ремонти, команди, питання й
    #            «без входу»: ремонт — це вихід, а не вада речі, а брак входу не є
    #            вадою РЕЧІ. Міркування правильне — але `зн` звідси йшло далі як
    #            ЄДИНЕ джерело того, що показати людині. Тобто функція сортування
    #            вирішувала, про що система має право сказати, і мовчки викидала
    #            цілий канал корпусу: `канал_3` (команди розкладки, K-CRA-11 /
    #            K-CHN-01) не доходив нікуди, а аксесуарні «входу нема» не ставали
    #            припущеннями (K-IO-03, `hard`).
    #   after  — повний вихід перевірки (він тут завжди був, і його викидали в `_`)
    #            дає два окремі виходи: третій канал і черга на вхід. Ключ
    #            сортування лишається тим самим, тобто ранжування не змінилось.
    import знахідка as _ЗН
    _усі_пари = _ЗН.без_повторів(_ЗН.усі(_повний))
    _у_ключі = {(z.get("правило"), str(z.get("суть"))[:120]) for z in зн}
    # ТРЕТІЙ КАНАЛ МАЄ ДВІ ФОРМИ, І ЦЕ НЕ НЕДОГЛЯД. `outer.команди_укладки` віддає
    # ЗНАХІДКИ (пояс тренча, піднятий комір — там є правило, сила й ремонт), а
    # `accessory.команди_розкладки` — ОПЦІЇ З КОМПРОМІСАМИ (річ, клас, допустимі
    # місця, наслідок кожного). Друге навмисно не знахідка: канонічний авторитет
    # домену відмовляється робити цей вибір правилом, тож система подає варіанти,
    # а не вердикт. Тому збирач знахідок їх і не бачить — його справа інша.
    _команди_зн = [dict(правило=z.get("правило"), суть=z.get("суть"),
                        чому=z.get("чому"), речі=z.get("речі"))
                   for ш, z in _усі_пари if "/команди" in ш]
    _опції = []
    for _г in (_повний.get("аксесуари"), _повний.get("верхній_шар")):
        if isinstance(_г, dict):
            _опції += list(_г.get("канал_3") or [])
    вих["канал_3"] = dict(команди=_команди_зн, опції=_опції)
    вих["черга_на_вхід"] = [z for ш, z in _усі_пари
                            if (z.get("регістр") == "питання" or z.get("сила") == "питання")
                            and (z.get("правило"), str(z.get("суть"))[:120]) not in _у_ключі]
    # Чеклісти надлишку й прісності (K-SYS-08/09) рахуються в `перевірити_образ` і
    # доти лишались усередині неї: єдиним споживачем був стенд. Тема-4 називає їх
    # обовʼязковими воротами видачі, тож вони мусять доїхати щонайменше до
    # промпту ремонту — там модель ще може щось із ними зробити.
    вих["чеклісти"] = _повний.get("чеклісти")
    вих["реєстри"] = _повний.get("реєстри")
    # ВИМКНЕНЕ РІШЕННЯМ ВЛАСНИКА 05.09.2026: правила розміру (припуск, прилягання,
    # тісність) — доки в каталозі нема мірок виробу; K-CRA-04 «прибери одну річ» — геть.
    # Тип фігури й силует лишаються.
    # K-COMP-01: ранг цього образу серед ІНШИХ, які модель дала на той самий випадок.
    # Без набору правило само себе утримує й каже це вголос — саме тому набір тут
    # необовʼязковий, а не вигаданий.
    if набір_близькостей:
        try:
            import outfit as _O2, coordination as _КО2
            зн = list(зн) + _O2.обмежити_вагу(
                _КО2.координація(_O2.елементи(речі),
                                 набір_кандидатів=[v for v in набір_близькостей if v is not None]))
        except Exception:
            pass
    зн = [z for z in зн if not _вимкнене(z)]
    # ДОПОВНЕННЯ СУДДІ ЗА НАЗВАМИ (05.09.2026, проби правил): базові правила читають поля
    # (виріз, візерунок, метал), яких у каталозі майже нема, — і мовчали на міні+декольте,
    # леопард+смужка, срібло при «теплих», рюкзак на весілля, паєтки вдень. Тут те саме
    # правило — з назви речі, силою hint/soft, з позначкою джерела.
    # ── ДЕДУП K-COL-10 — ЗА ПРАВИЛОМ, А НЕ ЗА НАБОРОМ РЕЧЕЙ (Н-V16-041) ──────
    # Ключ `(правило, речі)` на K-COL-10 не працював за побудовою: `outfit.принти`
    # судить лише ВИДИМІ речі (`видимі_id`, і образ проганяється у двох станах),
    # а `_доповнення_судді` — усі речі за назвою. Набори речей через це різні, і
    # ключі не збігались. Виміряно (леопард-верх + смужка-низ + клітинка-пальто):
    # у `/знахідки` лягали ТРИ K-COL-10 — «c1+c2» (у приміщенні), «c2+c3»
    # (надворі) і «c1+c2+c3» із назв, тобто одну проблему стиліст читав тричі.
    # Взято другий варіант наряду: для K-COL-10 у ключі лише ПРАВИЛО. Звужувати
    # `_доповнення_судді` до видимих речей — не варіант: воно й написане для
    # образів БЕЗ полів каталогу, і звуження зняло б знахідки там, де немає з чого
    # порахувати видимість. Решта правил доповнення ключ не міняють: у них по
    # одному виробнику, і набір речей у ключі там відрізняє два різні випадки.
    _ЗА_ПРАВИЛОМ = ("K-COL-10",)
    _ключ = lambda z: ((z.get("правило"),) if z.get("правило") in _ЗА_ПРАВИЛОМ
                       else (z.get("правило"), tuple(sorted(z.get("речі") or []))))
    _вже = {_ключ(z) for z in зн}
    for z in _доповнення_судді(речі, сценарій, драп):
        if _ключ(z) not in _вже:
            зн.append(z)
            _вже.add(_ключ(z))
    # НАМІР statement (тема-6/8): гучність — легітимна; конфлікт хром і кількість інтересу
    # важать удвічі менше, і це видно в суті
    if (сценарій or {}).get("intent") == "statement":
        for z in зн:
            if z.get("правило") in ("K-COL-02", "K-COMP-04", "K-INT-04", "K-COMP-03"):
                z["сила_нп"] = round(float(z.get("сила_нп") or 0) * 0.5, 2)
                z["суть"] = str(z.get("суть") or "") + " (намір statement: сила вдвічі менша)"
    # ВЕТО ЛЮДИНИ — АБСОЛЮТ (K-PC-08 у базі: «абсолютний фільтр», K-PER-05): знахідка стає блокером
    # `блокує` — ОДНОРІДНИЙ список ЗНАХІДОК-СЛОВНИКІВ із `composer._оцінити`; рядок нижче
    # (формування `вих["блокує"]`) кличе `.get` на кожному елементі. Дописаний сюди РЯДОК
    # клав у список чужий тип і валив увесь `перевірити_від_моделі` з AttributeError —
    # тобто найсильніше правило системи спрацьовувало рівно так, щоб знести суддю. Тому
    # сюди йде знахідка з підміненою `суть`, а не рядок: тип елемента не міняється, а
    # назовні контракт той самий (рядки з `суть`), бо перетворення робить рядок нижче.
    # Дедуплікація теж мусила переїхати: `б not in блокує` порівнювало рядок зі словниками
    # й НІКОЛИ не спрацьовувало б — той самий K-PC-08 лягав би двічі. Ключ — правило й речі.
    _мітка = lambda z: dict(z, суть="вето людини: %s" % str(z.get("суть") or "")[:80])
    _ключ = lambda z: (z.get("правило"), tuple(z.get("речі") or ()))
    # K-PC-08 УЖЕ лежить у `блокує`: `_оцінити` бере туди всі знахідки з `блокує=True`,
    # а вето несе саме його. Тому мітка ставиться НА МІСЦІ, а не другим записом — інакше
    # людина дістала б той самий блокер двічі, раз із префіксом і раз без.
    _позначені = set()
    _нов_блок = []
    for z in блокує:
        if isinstance(z, dict) and z.get("правило") == "K-PC-08":
            _позначені.add(_ключ(z)); _нов_блок.append(_мітка(z))
        else:
            _нов_блок.append(z)
    # …а якщо вето прийшло лише знахідкою (шлях, де `_оцінити` її не блокувало) — дописати.
    for z in зн:
        if z.get("правило") == "K-PC-08" and _ключ(z) not in _позначені:
            _позначені.add(_ключ(z)); _нов_блок.append(_мітка(z))
    блокує = _нов_блок
    # оголошені розриви моделі — ДО графа, щоб вузол напруги рахувався з ослабленими силами
    зн = list(зн) + list(вих.get("акцент") or [])
    зн, свідомі = _застосувати_свідомі(
        зн, (розриви if розриви is not None else свідомі_розриви(текст_моделі)), речі)
    вих["свідомі"] = свідомі
    г = _ГР.граф(зн, речі); в = _ГР.вузол_напруги(г)
    вих.update(знахідки=sorted(зн, key=lambda z: -(z.get("сила_нп") or 0.0)),
               граф=г, вузол=(в or {}).get("вузол"), рядок_вузла=_ГР.рядок_вузла(в, г),
               блокує=list(вих["структура"]) + [str(z.get("суть") or "")[:100] for z in блокує],
               сума_сил=сума,
               речі=[dict(id=r["id"], слот=r["слот"], назва=r.get("назва"),
                          **({"частина_комплекту": r["частина_комплекту"]} if r.get("частина_комплекту") else {}))
                     for r in речі])
    if текст_моделі:
        try:
            import language_gate as _МГ
            вих["мова"] = _МГ.перевірити(текст_моделі)
        except Exception as _e:
            вих["мова"] = dict(помилка=str(_e))
    return вих



