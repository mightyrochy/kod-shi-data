        # міст дописав `перевірено=True`, показ вивів порожню картку з трьома
        # сирими рядками). Тепер це блокер і явне «не перевірено», а речі їдуть
        # назовні, щоб показ мав із чого будувати картку.
        вих["чому"] = ("замало речей: %d — образ потребує щонайменше двох речей, "
                       "код не має що судити" % len(речі))
        вих["перевірено"] = False
        вих["блокує"] = list(вих["структура"]) + [
            "образ з однієї речі — це не образ: додай щонайменше взуття (або верх/низ до комплекту)"]
        вих["речі"] = [dict(id=r["id"], слот=r["слот"], назва=r.get("назва"),
                            **({"частина_комплекту": r["частина_комплекту"]} if r.get("частина_комплекту") else {}))
                       for r in речі]
