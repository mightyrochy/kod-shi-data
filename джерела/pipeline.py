# ПРОТОКОЛ ІМПОРТУЄТЬСЯ, А НЕ ПЕРЕПИСУЄТЬСЯ (Т-02). Версія обміну, імена схем і
# переліки слів (`ГІЛКИ`, класи температури, зони вето) лежать в одному місці —
