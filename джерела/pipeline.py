# ── РІШЕННЯ 30.08.2026: П'ЯТЬ НАЗВАНИХ ПОЛЮСІВ + РЕШТА ВІЛЬНИХ ────────────────
# ЩО ВИРІШЕНО. При запиті N образів перші п'ять дістають задум зі словника вище,
# решта (N−5) лишаються ВІЛЬНИМИ: ші вигадує задум сама й підписує його.
#
# ЧОМУ НЕ ДОПИСАНО ЩЕ П'ЯТЬ ПОЛЮСІВ. Дописати можна за хвилину — але кожен новий
# полюс був би вигаданий за столом, а не взятий із того, що працює. Словник із
# п'яти стоїть на операторах, які композитор реально вміє (O1–O5); шостий такої
# опори не має. Вигадати його зараз означало б увести п'ять некаліброваних
# констант у місце, де їх ніхто не міряє (правило 4: сила ≤ верифікація).
#
# ЧИМ ЦЕ РІШЕННЯ БУДЕ ПЕРЕГЛЯНУТО — умова названа наперед, щоб не загубилась:
#   · якщо у вердиктах «носитиму» ВІЛЬНІ образи виграють у названих — словник
#     звужується або зникає: полюси лише звужували ші там, де вона краща сама;
#   · якщо ші у вільних слотах раз за разом вигадує ОДИН і той самий задум і він
#     не збігається з жодним із п'яти — це готовий шостий полюс, здобутий
#     виміром, а не за столом: вписати його сюди;
#   · якщо вільні образи стабільно повторюють названі — вільних слотів забагато,
#     N зменшується до довжини словника.
# Носій даних для всіх трьох умов один: ПІДПИС кожного образу лягає в журнал
# поруч із вердиктом (bridge._вердикти_образів → поле `підпис`).
ВІЛЬНИХ_ЗАДУМІВ = "решта — твої власні задуми"


def _формат_відповіді(варіантів):
    """Що просити в моделі. Один образ — як було. N образів — самі рядки ОБРАЗ:.

    ЧОМУ БЕЗ ПРОЗИ ПРИ N > 1: проза коштує токени виходу, а вихід і є основна
    частина латентності виклику. Опис для людини пишеться в ОСТАННЬОМУ виклику,
    коли образ уже обрано (`промпт_вибору`); коду пояснення не потрібне.
    """
    if варіантів <= 1:
        return ["Останнім рядком відповіді дай «ОБРАЗ: id, id, …» — по одній речі на слот."]
    полюси = "; ".join("%s — %s" % (і, ч) for і, ч in ПОЛЮСИ_ОБРАЗУ[:варіантів])
    # ВІЛЬНІ СЛОТИ НАЗВАНІ ВГОЛОС, А НЕ ЛИШЕНІ МОВЧКИ. Доти зріз `[:варіантів]`
    # просто вичерпувався: на запиті 10 образів модель діставала п'ять задумів і
    # жодного слова про решту п'ять — тобто половина замовлення йшла без завдання,
    # і різниця між «вільний образ» і «модель не дочитала» була невідрізненна ні
    # для неї, ні потім для нас у журналі.
    _вільних = max(0, варіантів - len(ПОЛЮСИ_ОБРАЗУ))
    if _вільних:
        полюси += ". Ще %d образ%s — БЕЗ заданого задуму: %s, і кожен підпиши так, " \
                  "щоб задум було видно з підпису" % (
                      _вільних, "" if _вільних == 1 else ("и" if _вільних < 5 else "ів"),
                      ВІЛЬНИХ_ЗАДУМІВ)
    return [
        "Дай %d РІЗНИХ образів. Різних не дрібницею, а задумом: %s." % (варіантів, полюси),
        "Формат — рівно %d блоків, БЕЗ будь-якої іншої прози:" % варіантів,
        "    ПІДПИС: <3–5 слів, який це задум>",
        "    ОБРАЗ: id, id, … — по одній речі на слот",
        # МІСЦЕ ДЛЯ СВІДОМОГО ХОДУ НАЗВАНЕ ВСЕРЕДИНІ БЛОКУ, А НЕ «десь у відповіді».
        # Розбір ріже текст по образах і віддає кожному його ж рядки; рядок,
        # написаний не там, дістанеться сусідньому образу — тобто послабить чужу
        # знахідку й лишить свою в силі. Тому позиція тут — частина формату.
        "    СВІДОМО: <річ> — <чому>   ← лише якщо в ЦЬОМУ образі ти свідомо ламаєш "
        "умову; рядок ставиться одразу під його «ОБРАЗ:», інакше він припишеться "
        "сусідньому образу",
        "Пояснення не пиши: його попросять окремо, коли образ буде обрано.",
    ]


def _вітрина_ремонту(образи, кандидати, скільки_слотів=2, на_слот=12):
    """Речі, якими можна розвʼязати те, що тисне — саме в тих слотах, де тисне.

    ЧОМУ ЦЕ ІСНУЄ (31.08.2026). Промпт ремонту ніс лише ВЛАСНІ образи моделі:
    зміряно — 2 094 символи, 5 id, нуль кандидатів, нуль слотів. А кожен виклик іде
    свіжим контекстом без історії, тож на другій ітерації модель фізично не бачила
    жодної речі, крім тих, які сама вже обрала. Якщо ремонт вимагав ІНШОГО взуття,
    взуття не було звідки взяти — вона могла лише переставляти вже обране.
    Приймальня при цьому існувала: `ід_з_тексту` резолвить річ поза пулом із повного
    каталогу. Тобто приймальня була, вітрини не було.

    ЧОМУ НЕ ВЕСЬ ПУЛ. Повторити сотні речей у кожному виклику ремонту означало б
    платити за них удруге й утретє. Вітрина адресна: слоти беруться з ВУЗЛІВ
    напруги реальних образів — з того, що код зміряв на тому, що ші справді склала,
    а не з припущення. Речі, які модель уже взяла, виключаються: показувати їй те,
    що вона й так має, — не вибір.
    """
    if not образи or not кандидати:
        return []
    import collections as _c
    вузли = _c.Counter(о.get("вузол") for о in образи if о.get("вузол") in кандидати)
    if not вузли:
        return []
    взяті = {i for о in образи for i in (о.get("ід") or [])}
    # НОМЕРИ — З ПОВНОГО ПУЛУ, як їх бачила модель у першій ітерації і як їх
    # читає `ід_з_тексту`. Підмножина, пронумерована сама по собі, — інша нумерація.
    _нум = номери_речей(кандидати) if ПАКУВАТИ_ІНДЕКСОМ else ({}, {})
    рядки = []
    for слот, скільки in вузли.most_common(скільки_слотів):
        вільні = [r for r in (кандидати.get(слот) or []) if r.get("id") not in взяті]
        if not вільні:
            continue
        рядки.append("")
        рядки.append("── чим можна розвʼязати «%s» (вузол у %d з %d твоїх образів):"
                     % (слот, скільки, len(образи)))
        рядки += пакувати_кандидатів({слот: вільні[:на_слот]}, нумерація=_нум)[1:]
    # ── ДЕ МОЖНА ЛАМАТИ — З РЕАЛЬНИХ ОБРАЗІВ, А НЕ З ВИГАДАНИХ ─────────────
    # Слот розриву доти обирався в композиторі за 200 ВИГАДАНИХ комбінацій із
    # топ-5 на слот: образів, яких ніхто не збирав і не збиратиме. Після першої
    # ітерації на руках десять СПРАВЖНІХ образів, кожен уже проведений крізь граф
    # із вузлом напруги. Міряти по них і дешевше, і чесніше — той самий принцип,
    # яким прибрано власний образ коду: код судить складене, не вигадане.
    # МЕЖА ЛИШАЄТЬСЯ ТА САМА, що стерегла композитор: ламати можна лише далеко від
    # обличчя. Верх, сукня й верхній шар не пропонуються ніколи — там колір біля
    # обличчя вирішує (K-CLR-02), і розрив коштував би головного правила системи.
    _далеко = [(с, n) for с, n in вузли.most_common()
               if с not in ("верх", "сукня", "комплект", "верхній_шар")]
    if _далеко:
        _с, _n = _далеко[0]
        рядки.append("")
        рядки.append("ДЕ МОЖНА ЛАМАТИ ПАЛІТРУ: слот «%s» — вузол у %d з %d ТВОЇХ образів, і він "
                     "далеко від обличчя, тож колірні правила біля обличчя тут не діють. "
                     "Якщо береш туди річ поза палітрою — скажи рядком «СВІДОМО: <річ> — <чому>»: "
                     "оголошений розрив судиться мʼякше, неоголошений — як помилка."
                     % (_с, _n, len(образи)))
    if рядки:
        рядки.append("")
        рядки.append("Це НЕ наказ міняти саме там. Це речі, яких ти ще не брала, у слоті, "
                     "де в твоїх образах сходиться найбільше умов. Брати їх не обовʼязково.")
    return рядки


def образ_рядком(о, кандидати=None, ном=None):
    """«взуття: #12·33 Босоніжки… · низ: #45·10 Штани…» — образ зі СЛОТАМИ.

    ЧОМУ (02.09.2026, прогін 21:24: три образи поспіль із двома взуттями).
    Доти образ друкувався голими id: «ж-04756@miraton.ua, ж-00132@gepur.com».
    Модель не бачила, який id — взуття, тож коли вітрина ремонту пропонувала
    інше взуття, вона ДОДАВАЛА його, а не заміняла: замінити означало б
    вгадати, який із голих id прибрати. А до правки нумерації вітрини 02.09
    додане взуття не резолвилось узагалі й випадало мовчки — тому «раніше
    такого не було»: помилка була, її не було видно.
    Тепер кожна річ образу підписана слотом і номером із того самого пулу,
    що бачить модель, — замінити взуття означає замінити рядок «взуття: …»."""
    частини = []
    за_ід = {}
    for сл, пул in (кандидати or {}).items():
        for r in пул:
            if r.get("id"): за_ід.setdefault(r["id"], (сл, r.get("назва") or ""))
    for і in (о.get("ід") or []):
        сл, назва = за_ід.get(і, ("?", ""))
        мітка = ("#%d·%s" % ном[і]) if ном and і in ном else str(і)
        частини.append(("%s: %s %s" % (сл, мітка, назва[:40])).rstrip())
    return " · ".join(частини) if частини else ", ".join(str(x) for x in (о.get("ід") or []))


