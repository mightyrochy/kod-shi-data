def паспорт_з_json(текст, сценарій, слова):
    """JSON моделі → паспорт із дефолтами з обраного сценарію. Модель мовчить або
    бреше форматом → паспорт будується з того, що обрала людина, і це видно у `джерело`."""
    сц = dict(сценарій or {})
    п = dict(подія=str(слова or "").strip() or (сц.get("нагода") or ""), формат="невідомо",
             тривалість_год=None, рух="невідомо", дрес_код=сц.get("дрес_код"), ошатність=None,
             година=сц.get("година"), темп_c=сц.get("темп_c"), опади="невідомо", намір="conventional",
             бажання=[], вето=dict(типи=[], тканини=[], принти=[], кольори=[], зони=[]),
             настрій=[], невідомо=[], джерело="сценарій (модель не відповіла)",
             нагода=сц.get("нагода"), місце=сц.get("місце"), слова=str(слова or "").strip())
    т = str(текст or "").strip()
    об = None
    if т:
        м = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", т, re.S)
        сир = м.group(1) if м else т[т.find("{"):т.rfind("}") + 1]
        try:
            об = _json_.loads(сир)
        except Exception:
            об = None
    if not isinstance(об, dict):
        return п
    п["джерело"] = "модель"
    for k in ("подія", "формат", "рух", "дрес_код", "опади"):
        if об.get(k) not in (None, "", []): п[k] = str(об[k]).strip()
    for k in ("тривалість_год", "година", "темп_c"):
        try:
            if об.get(k) not in (None, ""): п[k] = float(об[k]) if k != "година" else int(об[k])
        except (TypeError, ValueError):
            pass
    if isinstance(об.get("ошатність"), (list, tuple)) and len(об["ошатність"]) == 2:
        try:
            a, b = int(об["ошатність"][0]), int(об["ошатність"][1])
            п["ошатність"] = [max(1, min(10, min(a, b))), max(1, min(10, max(a, b)))]
        except (TypeError, ValueError):
            pass
    if str(об.get("намір") or "").strip() in ("conventional", "statement"):
        п["намір"] = str(об["намір"]).strip()
    for k in ("бажання", "настрій", "невідомо"):
        if isinstance(об.get(k), list):
            п[k] = [str(x).strip() for x in об[k] if str(x).strip()][:8]
    if isinstance(об.get("вето"), dict):
        for k in п["вето"]:
            v = об["вето"].get(k)
            if isinstance(v, list): п["вето"][k] = [str(x).strip() for x in v if str(x).strip()][:8]
    try:
        if об.get("ноги_вище_см") not in (None, ""): п["ноги_вище_см"] = float(об["ноги_вище_см"])
    except (TypeError, ValueError):
        pass
    return п


def паспорт_рядком(п):
    """Паспорт словами — ОДИН текст випадку для всіх чотирьох рук і шапки показу."""
    if not п:
        return ""
    р = [п.get("подія") or ""]
    if п.get("формат") and п["формат"] != "невідомо": р.append(п["формат"])
    if п.get("тривалість_год"): р.append("близько %g год" % float(п["тривалість_год"]))
    if п.get("рух") and п["рух"] != "невідомо": р.append(п["рух"])
    if п.get("дрес_код"): р.append("дрес-код %s" % п["дрес_код"])
    if п.get("година") is not None: р.append("%02d:00" % int(п["година"]))
    if п.get("темп_c") is not None: р.append("%g °C" % float(п["темп_c"]))
    if п.get("опади") == "так": р.append("опади")
    рядок = ", ".join(x for x in р if x)
    if п.get("бажання"): рядок += ". Хоче: " + "; ".join(п["бажання"])
    вето = [w for k in ("типи", "тканини", "принти", "кольори", "зони") for w in (п.get("вето") or {}).get(k, [])]
    if вето: рядок += ". Не хоче: " + "; ".join(вето)
    if п.get("настрій"): рядок += ". Настрій: " + ", ".join(п["настрій"])
    return рядок


