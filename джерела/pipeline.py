import json as _json_
import re

def _json_у_рядки(текст):
    """JSON від моделі → ті самі рядки ПІДПИС/ОБРАЗ/СВІДОМО/ЧОМУ/ПОТРІБНО, які розбирає
    решта коду. Одна точка розбору: або весь об'єкт прочитано, або він не JSON і текст
    іде старим шляхом. Часткової мовчазної втрати не буває (04.09, вердикт 7)."""
    т = текст.strip()
    if not т:
        return текст
    м = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", т, re.S)
    сир = м.group(1) if м else None
    if сир is None:
        a, b = т.find("{"), т.rfind("}")
        if a < 0 or b <= a:
            return текст
        сир = т[a:b + 1]
    try:
        об = _json_.loads(сир)
    except Exception:
        return текст
    if not isinstance(об, dict):
        return текст
    def _блок(о, чому=None):
        р = []
        if о.get("підпис"): р.append("ПІДПИС: %s" % str(о["підпис"]).strip())
        if чому: р.append("ЧОМУ: %s" % str(чому).strip())
        речі = о.get("речі") or о.get("образ") or []
        if isinstance(речі, str): речі = [речі]
        р.append("ОБРАЗ: " + ", ".join(str(x).strip() for x in речі if str(x).strip()))
        for с in (о.get("свідомо") or []):
            if str(с).strip(): р.append("СВІДОМО: %s" % str(с).strip())
        return р
    рядки = []
    if isinstance(об.get("образи"), list):
        for о in об["образи"]:
            if isinstance(о, dict): рядки += _блок(о)
    elif об.get("речі") or об.get("образ"):
        рядки += _блок(об, чому=об.get("чому"))
    else:
        return текст
    for п in (об.get("потрібно") or []):
        if str(п).strip(): рядки.append("ПОТРІБНО: %s" % str(п).strip())
    return "\n".join(рядки)


def запити_речей_з_тексту(текст):
    """Рядки «ПОТРІБНО: …» (з JSON-поля «потрібно») — прохання моделі про річ поза
    списком, словами. Це право ші, про яке домовлялися: код шукає по всьому каталогу."""
    т = _json_у_рядки(str(текст or ""))
