def підготувати(F, слоти=("верх", "низ", "взуття", "сумка"), source="uncontrolled",
                каталог=None, шлях_фіду=None, ліміт_фото=None,
                intent="conventional", якір_тон=None, фокус=None, драп=None,
                самозвіт=None, мета=None, мета_слова=None, прикраси=None, зріст_см=None,
                нагода=None, місце=None, формат=None, дрес_код=None, година=None,
                господар=False, креативне=False, роль=None, супутник_рівень=None,
                активність=None, сезон=None, темп_c=None, тіло=None,
                жорстке_ні=None, мікс_нагод=None, ваги_цілей=None,
                життєвий_перехід=None, форма_повна=True, lex=None):
    """Пакет для ші-стиліста: хто ця людина, що просить нагода, які палітри законні,
    які реальні речі під кожне вікно, і чого система не знає.

    `каталог` — уже виміряний список SKU (feed.прогін().каталог-подібний) АБО
    `шлях_фіду` — YML магазину, тоді фід міряється тут. Без жодного з них пакет
    віддається БЕЗ кандидатів і чесно це каже: вікна без каталогу — це припущення,
    що така річ існує."""
    import outfit as O, palette as P, profile as PR
    import реєстр_правил as _РЕЄСТР, суд_образу as _СУД, формальність as _ФОРМ   # Н-02-01, сесія 4
    _PR = PR

    особа = O.контраст_особи(F, source)
    if not особа.get("доступно"):
        return dict(готово=False, чому=особа.get("чому"),
                    що_робити="потрібні шкіра й волосся в профілі (colorspace.features)")

    сцен = _ФОРМ.сценарій(місце=місце, код=_ФОРМ.код_дрес(дрес_код), година=година,
                          господар=господар, креативне=креативне, роль=роль,
                          супутник_рівень=супутник_рівень, активність=активність,
                          сезон=сезон, нагода=нагода, темп_c=темп_c)

    # ── ВАГИ ЦІЛЕЙ → МЕТА. Поле більше не декоративне ────────────────────────
    # Доти `ваги_цілей` і `мікс_нагод` збирались і не читались НІДЕ, а `мета` була
    # прибита до "лестити" по всій системі. Тепер ваги усереднюються по РЕАЛЬНОМУ
    # міксу нагод і дають мету, яку вже вміють читати palette.нейтраль_якір і
    # посадка.краї. Нових правил не додано — під'єднано наявний перемикач.
    _ваги_зваж, _чому_ваг = _PR.ваги_за_нагодою(ваги_цілей, мікс_нагод)
    # ── МЕТА ЗІ СЛІВ ПРО ЦЕЙ ВИХІД ПЕРЕВАЖАЄ ВАГИ ПРОФІЛЮ (рядок 108, 20.09.2026) ─
    # Рішення власника: мета — «питання сценарію, а не профілю». Паспорт випадку
    # несе її (`паспорт_нагоди.СХЕМА_ПАСПОРТА["мета"]`, лише зі слів жінки), шов
    # доставляє як поле нагоди (`сценарій.ПОЛЯ`). Коли слів не було — як доти:
    # дефолт із ваг, і `чому_мети` чесно каже, що це не її вибір.
    _мета_ваг, _чому_ваг_мети = _PR.мета_з_ваг(_ваги_зваж, нагода=нагода)
    if мета in _PR.МЕТИ:
        чому_мети = ("зі слів жінки про цей вихід: „%s“ → мета «%s» (паспорт випадку, K-IO-02); "
                     "переважає мету з ваг профілю («%s»: %s)"
                     % (str(мета_слова or "—").strip()[:120], мета, _мета_ваг,
                        _чому_ваг_мети.split(".")[0]))
    else:
        мета, чому_мети = _мета_ваг, _чому_ваг_мети

    # ── САМОЗВІТ ЇДЕ ПОРУЧ ІЗ ДРАПОМ, А НЕ ЗАМІСТЬ НЬОГО (Н-V03-007) ──────────
    # Це два РІЗНІ канали з однієї відповіді людини: `драп` читає `нейтраль_якір`
    # (вікно b* нейтралі), `самозвіт` — `palettes.осі` (бік осі тону). Доти другий
    # каналу до палітри не мав узагалі: параметра не було ні тут, ні в
    # `розвилка_специфікацій`, ні в `специфікація`, тож `palettes.осі` на живому
    # шляху завжди утримувала вісь (undertone 0.15 < MIN_TO_EMIT на uncontrolled)
    # і віддавала ОБИДВІ температурні версії кожної сім'ї — 347° з 360.
    # ── ВІДСТАНЬ ОГЛЯДУ ВХОДИТЬ У ДОБІР, А НЕ ЛИШЕ В СУД (K-COND-04) ─────────
    # ЩО ЦЕ МІНЯЄ. `нейтраль_якір` множить приобличчеву вагу слота на силу підтону
    # і з добутку виводить ШИРИНУ вікна b* нейтралі — того самого, що їде запитом
    # у каталог (`запит_у_фід`). Доти вага слота була одна на всі нагоди, тобто
    # запит до каталогу не відрізняв вечерю за столом від весілля на повний зріст.
    # Тепер відрізняє: на «розмові» вікно нейтралі біля обличчя вужчає (пул
    # суворіший саме там, де людину роздивляються), на «повний зріст» ширшає, а
    # далекі слоти — навпаки. `формат` оголошений у `сценарій.ПОЛЯ` і приїжджає
    # сюди тим самим шляхом, що `місце` й `нагода`; коли жодне з трьох у таблицю
    # не веде, `дистанція` = None і добір лишається таким, яким був.
    import дистанція as _ДИСТ
    _дист = _ДИСТ.з_сценарію(dict(місце=місце, формат=формат, нагода=нагода))
    розв = P.розвилка_специфікацій(F, list(слоти), source=source, intent=intent,
                                   якір_тон=якір_тон, фокус=фокус, драп=драп, мета=мета,
                                   самозвіт=самозвіт, дистанція=_дист.get("дистанція"))

    # ── реальні речі під вікна ────────────────────────────────────────────────
    # ── ЖОРСТКЕ «НІ» — АБСОЛЮТНИЙ ФІЛЬТР, І ВІН МУСИТЬ СТОЯТИ ДО ВІКОН ────────
    # Тема-6 PART 12 називає це найочевидніше правильним правилом теми, якому доти не
    # було де жити. Фільтр стоїть ПЕРЕД покриттям навмисно: інакше вікно рахувало б
    # кандидатів, яких людина не вдягне, і «порожньо=False» брехало б. Скільки саме
    # відкинуто — їде в пакет, бо це і є ціна списку заборон.
    кат, звіт_фіду, відкинуто_ні = каталог, None, []
    # СЛІД ПОРУЧ ІЗ ПОЛЕМ: поле каже читачеві виходу, чиє це рішення, запис —
    # логові, на чому воно спрацювало (скільки речей прибрано і за яким словом).
    # Запис стоїть ПІСЛЯ фільтра, нижче, бо число до фільтра ще не існує.
    if кат is None and шлях_фіду:
        import feed
        зфід = [г["запит_у_фід"] for г in розв["розвилка"] if г.get("запит_у_фід")]
        звіт_фіду = feed.прогін(шлях_фіду, зфід, ліміт_фото=ліміт_фото)
        кат = звіт_фіду.get("каталог")
    if кат and жорстке_ні:
        кат, відкинуто_ні = _PR.жорстке_ні_фільтр(кат, жорстке_ні)
        # П.14 (20.09.2026): застава знята. `trace` — модуль ядра, `запис` тотальний,
        # і ловилась тут лише помилка коду в `%`-підстановці вище. Ковтання лишало
        # лог без K-PER-05 — тобто без рядка про те, СКІЛЬКИ речей прибрано жорстким
        # «ні» людини, — і мовчало про це. Летить у `bridge.виклик` → `помилка` + `код`.
        import trace as _СЛ_PER
        _СЛ_PER.запис("K-PER-05", "сенсорне обмеження: межа людини — абсолютний фільтр",
                      "підготувати", значення="%d речей прибрано за %s"
                      % (len(відкинуто_ні), ", ".join("«%s»" % x for x in жорстке_ні)),
                      сила=1.0, напрям="фільтр каталогу, не оцінка")
    for г in розв["розвилка"]:
        q = г.get("запит_у_фід")
        if not q: continue
        if кат:
            import feed
            г["кандидати"] = feed.покриття(q, кат, словник=lex)
            г["порожніх_вікон"] = sum(1 for r in г["кандидати"] if r["порожньо"])
        else:
            г["кандидати"] = None
            г["порожніх_вікон"] = None

    # ── ЩО ШУКАТИ ПО ФОРМІ (парне до колірної розвилки) ───────────────────────
    # Доти пакет казав стилістові, які КОЛЬОРИ шукати, і мовчав про крій та довжину.
    # ЧОМУ ЦЕ ТЕПЕР ЗА ПРАПОРЦЕМ. Виміряно на стенді: `специфікація` — 93% часу
    # всього виклику «запити» (1.20 с із 1.29 на CPython, ×2 бо рука C рахується
    # на донорському тілі). У Pyodide на телефоні це 4–6 с чекання на випадок.
    # При цьому єдине, що з неї доживало до брифа, — один рядок про довжину
    # верху: ранжування кроїв віддає `гіперграф.простір` за 0.03 с, і воно
    # неперервне, а не бінарне. Повна сітка потрібна шару retrieval (запит у
    # фід по 1485 комбінаціях), а не брифу — тому вона лишається доступною,
    # але вимикається там, де її ніхто не читає.
    форма = None
    if тіло is not None and форма_повна:
        import silhouette as _СЛ
        форма = _СЛ.специфікація(тіло, intent=intent, мета=мета)

    # ── чого бракує на вході ──────────────────────────────────────────────────
    аудит = PR.аудит(F, source=source, зріст_см=зріст_см, драп=драп, нагода=нагода,
                     сценарій_входи=dict(місце=місце, година=година, господар=господар,
                                         супутник_рівень=супутник_рівень,
                                         активність=активність))
    # СЛІД ПОРУЧ ІЗ ПОЛЕМ, А НЕ ЗАМІСТЬ НЬОГО (K-IO-02, друге проходження гейта).
    # Поле `бракує_входів.правило` нижче каже ЧИТАЧЕВІ ВИХОДУ, чиє це рішення;
    # запис тут каже ЛОГОВІ, на чому воно спрацювало — на скількох порожніх полях
    # профілю. Два різні споживачі (`trace.py`: «запис читає ЛОГ, знахідку читає
    # споживач»), і одного замість двох тут не досить: без числа лог не може
    # відрізнити «питань нема, бо профіль повний» від «шар не викликався».
    # П.14 (20.09.2026): застава знята. `trace` — модуль ядра, `запис` тотальний.
    # Ковталась лише помилка коду вище, а разом з нею — саме та відмінність, заради
    # якої цей запис і стоїть (абзац над ним): «питань нема, бо профіль повний»
    # проти «шар не викликався». Летить у `bridge.виклик` → `помилка` + `код`.
    import trace as _СЛ_IO
    _СЛ_IO.запис("K-IO-02", "питати рівно про те, чого бракує", "підготувати",
                 значення="%d питань онбордингу, %d полів «не питати»"
                 % (len(аудит.get("бракує_онбордингу") or []),
                    len(аудит.get("не_питати") or {})),
                 сила=None, напрям="протокол браку даних")
    # КОНТРАКТ_ПРИНТУ тут нарешті щось вирішує: він каже, які входи правил принту
    # існують, а які ні — стиліст бачить, які правила замовкнуть, ще до вибору речей
    контракт_принту = {k: v for k, v in P.КОНТРАКТ_ПРИНТУ.items()
                       if v["статус"] == "НЕМА ВИМІРУ"}

    return dict(
        готово=True,
        особа=dict(**особа, температура=P.температура(F, source, intent),
                   бік_b=P.бік_b_проти_людини(F),      # R-COL-16: рядок жінці в brief
                   масштаб=PR.масштаб(зріст_см) if зріст_см else None,
                   гейт_джерела=__import__("colorspace").gate_conclusions(
                       source, se_L=особа.get("розкид"))),     # R-PC-10: регіональний шум профілю
        сценарій=сцен,
        # ВІДСТАНЬ ОГЛЯДУ ЇДЕ В ПАКЕТ РАЗОМ ІЗ ПРИЧИНОЮ (K-COND-04). Не для
        # краси: пакет — це те, що бачить шар пояснень, і «вага приобличчя
        # ключована на розмову» та «вага одна на всі сцени, бо місця не сказали»
        # — два різні стани, які без цього поля виглядали б однаково.
        дистанція=_дист,
        палітри=розв,
        форма=форма or dict(проганялось=False,
                            чому="не передано тіло — крій і довжина не виводяться"),
        каталог_звіт=(dict(офферів=звіт_фіду["офферів"], з_кольором=звіт_фіду["з_кольором"],
                           відкинуто_контролем=звіт_фіду["відкинуто_контролем"],
                           без_слота=звіт_фіду["без_слота"],
                           розкид_каталогу=звіт_фіду["розкид_каталогу"])
                      if звіт_фіду else None),
        людина=dict(
            # ── ФІЛЬТР НАЗИВАЄ СВОЄ ПРАВИЛО (K-PER-05, друге проходження гейта) ──
            # ЩО ЦЕ МІНЯЄ (правило 3, before/after). Сенсорне обмеження ЛОВИТЬСЯ
            # й ПРАЦЮЄ: `profile.жорстке_ні_фільтр` предикатом над виведеним полем
            # `каблук` відкидає 1 028 пар із 1 950 на «не ношу підбори»
            # (`проби/per_K-PER-05.py`). Чого у виході не було — ID: ні тут, ні в
            # гейті `перевірити_образ`. Отже правило з найтвердішою силою теми-6
            # («hard on the person's authority alone») міняло КАТАЛОГ і в жодному
            # рядку виходу себе не називало.
            # ID СТОЇТЬ БІЛЯ ЧИСЛА, А НЕ НАД УСІМ БЛОКОМ: у `людина` лежать три
            # різні речі (жорстке «ні», мікс нагод, ваги цілей), і одне
            # `правило` над ними приписало б K-PER-05 ще й ваги.
            жорстке_ні_правило="K-PER-05",
            жорстке_ні=list(жорстке_ні or []),
            відкинуто_за_жорстким_ні=len(відкинуто_ні),
            приклади_відкинутих=відкинуто_ні[:5],
            мікс_нагод=мікс_нагод,
            ваги_цілей=ваги_цілей,
            життєвий_перехід=життєвий_перехід,
            мета=мета, чому_мети=чому_мети,
            ваги_зважені=_ваги_зваж, чому_ваг=_чому_ваг,
            # `прикраси` (рядок 108): бажання про метал прикрас З ЦИМ ОБРАЗОМ зі слів
            # жінки. Без нього добір слота прикрас іде за рекомендацією температури
            # (`палітра_температура`), а суд K-COL-06-M звіряє лише з драпіровкою
            # профілю — і це названо тут, а не вдається, ніби вхід є.
            прикраси=прикраси,
            нема_входів=[k for k, v in (("жорстке_ні", жорстке_ні),
                                        ("мікс_нагод", мікс_нагод),
                                        ("ваги_цілей", ваги_цілей),
                                        ("прикраси", прикраси)) if not v],
            чому_важить="тема-6 PART 12: без цих трьох полів шар елісітації не має де "
                        "жити. `жорстке_ні` — абсолютний фільтр (річ не показується "
                        "взагалі), `мікс_нагод` і `ваги_цілей` — ваги. Порожні поля "
                        "означають, що правила теми-6 мовчать, а не що обмежень нема"),
        # ── K-TIME-01: «ПЕРЕМІРЯТИ, А НЕ ПЕРЕНАЗВАТИ» ЇДЕ РАЗОМ ІЗ БРАКОМ ────
        # `profile.аудит` рахує ще два поля — `переміряти` (риси, чий ЗАЯВЛЕНИЙ зсув
        # перевищив поріг: перефарбування, сивина, засмага) і `вимога` (що саме
        # робити), — і вони не входили в жоден вихід узагалі. Це виконувана форма
        # K-TIME-01: зміна волосся вимагає НОВОГО ВИМІРУ, а не нової мітки, бо далі
        # вікна каталогу рахуються на числі, якого ніхто не бачив. Поле рахувалось
        # і вмирало разом із викликом.
        # ── КАНАЛ НАЗИВАЄ СВОЄ ПРАВИЛО (друге проходження гейта досяжності) ──
        # ЩО ЦЕ МІНЯЄ (правило 3, before/after). Поле поїхало назовні 17.09.2026,
        # і це закрило «правило мовчить». Лишилось друге: у виході НЕ СТОЯЛО
        # «K-IO-02» — ні тут, ні в `bridge`, ні в показі. Тобто читач виходу
        # бачив вісім питань і не мав як дізнатися, ЧИЄ це рішення й на якій
        # підставі їх рівно вісім; а гейт досяжності чесно рахував правило таким,
        # що себе не називає (`проби/io_K-IO-02.py` друкує сам канал, але ID у
        # ньому був лише в докстрінгу проби).
        # ЧОМУ ПОЛЕМ, А НЕ ЗНАХІДКОЮ. Знахідка — це вирок над РІЧЧЮ; тут вироку
        # нема й бути не може: список питань адресований тому, хто веде діалог, і
        # `реєстр_правил._зн` над ним дав би рядок, з яким людина нічого не
        # зробить (та сама межа, по якій K-COMP-01 у `зведення.py`).
        бракує_входів=dict(правило="K-IO-02",
                           онбординг=аудит.get("бракує_онбордингу"),
                           не_питати=аудит.get("не_питати"),
                           переміряти=аудит.get("переміряти"),
                           вимога_переміряти=аудит.get("вимога"),
                           правила_принту_без_виміру=контракт_принту),
        обмеження=status.список(),
        як_читати=(
            "ВИБІР РЕЧЕЙ — ЗА ВАМИ. Код не ранжує палітри й не зводить знахідки в бал: "
            "кожна гілка — законна, ваги ПОРЯДКОВІ, не виміряні. `кандидати` кажуть, де "
            "вікно порожнє в РЕАЛЬНОМУ каталозі (тоді або ширше вікно, або інша гілка). "
            "`форма` — дзеркало палітр по осі крою: що шукати, а не що виправляти; "
            "її поле `роздільність` каже, наскільки цей фільтр насправді звужує простір. "
            "`обмеження` — чого числа не знають; читати перед тим, як довіряти силі. "
            "Зібравши образ, віддайте його в перевірити_образ() — там знахідки й ремонти."))


# ─────────────────────────── ПІСЛЯ ВИБОРУ ───────────────────────────

def перевірити_образ(F, речі, source="uncontrolled", тіло=None,
                     вето_покриття=None, тон_колготи=None, жорстке_ні=None,
                     реагенти=None, тривалість_год=None, поверхня=None,
                     гардероб=None, заявлена_колона=False, **kw):
    """Ші-стиліст обрав речі — тут вони перевіряються. Повертає і сирий review, і
    контракт виходу (`для_стиліста`), і результат інваріанта (`перевірити_контракт`):
    обидва були написані й нікому не потрібні, бо ланцюжка не існувало.

    `тіло` — вихід посадка.тіло(зріст, обхвати[, рівні_см]). Коли він переданий і речі
    несуть свої висоти (верх_см/низ_см із розмірної таблиці), додатково проганяється
    шар посадки й силуету. Без тіла шар мовчить і каже це вголос: колірний вердикт над
    річчю, яка не сидить, — саме той провал, від якого рулбук ставить посадку в P0.
    Знахідки посадки їдуть ОКРЕМИМ ключем, а не в стани: вони не залежать від того,
    надворі людина чи в приміщенні, і змішувати дві різні осі в один список означало б
    втратити цю різницю."""
    import outfit as O, profile as PR
    import реєстр_правил as _РЕЄСТР, суд_образу as _СУД, формальність as _ФОРМ   # Н-02-01, сесія 4
    # ── ТЕПЛОВИЙ ВНЕСОК СТАВИТЬСЯ ДО review, І ЦЕ НЕ ДЕТАЛЬ ПОРЯДКУ ───────────
    # ЗНАЙДЕНО ПРОГОНОМ: перша версія рахувала його поруч із рештою гілки теми-11,
    # тобто ПІСЛЯ `суд_образу.review` — і K-WEA-01 устигав порахувати тренч штукою, а
    # виправлення приїжджало до вже виданої знахідки. Число входить у лічбу шарів,
    # отже мусить стояти раніше за того, хто рахує.
    import outer as _ВШ0
    _тф0 = _ВШ0.теплова_функція(речі)
    if _тф0.get("є"):
        for _р in речі:
            if _р.get("слот") == "верхній_шар":
                _р["тепловий_внесок"] = _тф0["тепловий_внесок"]
    # ── ШОВ ПЕРЕДАЄ РІВНО ТЕ, ЩО СПОЖИВАЧ ОГОЛОСИВ (08.09.2026) ──────────────
    # ЩО ТУТ СТОЯЛО І ЧОМУ ЦЕ НЕ ПРАЦЮВАЛО. Відсікання ключів на `_`, дописане
    # 05.09 після того, як «руки 3/4 падали TypeError». Це був ЕКЗЕМПЛЯРНИЙ фікс:
    # він прибирав два відомі службові ключі й нічого не казав про наступний. Клас
    # повторився 07.09, щойно в нагоді зʼявились `спец` і `запити` (вхід K-ACC-07):
    # `review()` їх не приймає, і TypeError знову валив увесь суддівський шлях.
    #
    # Це третій випадок ОДНОГО класу за три дні, і жодного з них не спіймав жоден
    # гейт: `gate_e2e` і `pair_test` не викликають `перевірити_образ` узагалі.
    # Отже лікується не уважність, а сам шов: `**kw`, що їде крізь чотири шари,
    # рано чи пізно принесе ключ, якого наступний шар не оголошував.
    #
    # ВІДБІР ЗА СИГНАТУРОЮ, А НЕ ЗА СПИСКОМ ІМЕН: список імен — це той самий
    # рукописний білий список, з якого починалась уся сесія. Сигнатура ж не може
    # розійтися з функцією, бо вона і є функція. Те, що не пройшло, не зникає
    # мовчки — воно лягає в `_не_для_review` і виходить із результатом.
    # ── ПЛОЩА З ГЕОМЕТРІЇ, КОЛИ КРАЇ ВИМІРЯНІ (Н-outfit-1-081) ───────────────
    # Другий і останній вхід суду: тут образ приходить ГОТОВИМ разом із тілом, і
    # докстрінг вище вже обіцяє, що «речі несуть свої висоти (верх_см/низ_см із
    # розмірної таблиці)». Доти ця обіцянка нічого не давала колірному шару: площі
    # не було, `джерело_площі` не ставив ніхто, і пʼять колірних правил утримувались
    # навіть над образом із повністю виміряними краями. `review` тіла не приймає (і
    # не має: це шар кольору), тож шов саме тут — поруч із `_посадка`, єдиним іншим
    # споживачем геометрії на цьому рівні.
    речі, _звіт_площ = O.площі_з_геометрії(речі, тіло)
    import inspect as _inspect
    _приймає = set(_inspect.signature(_СУД.review).parameters)
    _для_review = {k: v for k, v in kw.items() if k in _приймає}
    _відсіяно = sorted(k for k in kw if k not in _приймає)
    рез = _СУД.review(F, речі, source=source, **_для_review)
    порушення = _СУД.перевірити_контракт(рез)
    вих = _СУД.для_стиліста(рез)
    if _відсіяно:
        # не мовчки: шов має право не передати ключ, але не має права про це змовчати
        вих["не_для_review"] = _відсіяно
    вих["інваріант"] = (порушення or "тримається: кожна знахідка несе неперервну силу "
                                     "з названим джерелом")
    вих["особа"] = рез["особа"]
    вих["посадка"] = _посадка(тіло, речі, kw.get("intent", "conventional"),
                              kw.get("мета", "лестити"), тон_колготи=тон_колготи)

    # ── ШІСТЬ ПРАВИЛ, ЯКІ ІСНУВАЛИ Й НЕ БУЛИ ПІД'ЄДНАНІ ──────────────────────
    # K-PC-08, K-CRA-04, K-INT-04, K-MAT-01, K-SIL-06 (+K-SHO-02 у _посадка).
    # Правило, реалізоване й не викликане з конвеєра, не міняє жодного рішення —
    # це рівно те, у чому я щойно звинуватив корпус. Тому вони тут.
    # ── ЖОРСТКЕ «НІ» ТУТ САМЕ ТОМУ, ЩО ВОНО ВЖЕ Є В `підготувати` ────────────
    # ЗНАЙДЕНО НАСКРІЗНИМ ПРОГОНОМ: фільтр стояв ЛИШЕ у гілці обчислення вікон.
    # Композитор, що бере речі іншим шляхом (зі свого пошуку, з готового образу, з
    # історії), обходив його повністю — і образ із річчю під абсолютною забороною
    # проходив перевірку БЕЗ ЖОДНОГО СЛОВА. Абсолютний фільтр, який діє в одній
    # гілці з двох, не є абсолютним; він є звичкою.
    # Тут він не відкидає річ мовчки (образ уже зібрано — мовчазне зникнення речі
    # заплутало б), а виносить ГЕЙТ: видно, що саме порушено й чому.
    зн_ні = []
    if жорстке_ні:
        _, відкинуті = PR.жорстке_ні_фільтр(речі, жорстке_ні)
        for в in відкинуті:
            зн_ні.append(dict(_РЕЄСТР._зн(
                "профіль", "hard",
                "«%s» під жорстким «ні»" % (в.get("назва") or в.get("id")),
                [в.get("назва") or в.get("id")],
                "збіг із «%s» — це особиста межа, названа людиною. Обґрунтування не "
                "потрібне, і система не пропонує спробувати (тема-6 PART 12)"
                % в.get("через"),
                ремонт=["інша річ у цьому слоті"]),
                # `регістр="гейт", блокує=True` поверх `_зн` знято Н-02-05 разом із
                # трьома іншими механізмами регістру: гейт видає `регістр()` з єдиної
                # таблиці — `ПОЛІТИКА_РЕГІСТРУ["профіль"]`, підстава `МЕЖА_ЛЮДИНИ`.
                # Ключ таблиці тут не код правила, а те, що стоїть у полі `правило`
                # цієї знахідки: жорстке «ні» — це межа людини, а не правило корпусу.
                сила_нп=1.0,
                сила_нп_джерело="межу встановила людина, не вимір",
                # ── K-PER-05 НАЗИВАЄ СЕБЕ НА ЦІЙ ЗНАХІДЦІ (друге проходження) ──
                # `правило` тут лишається «профіль», і це НЕ описка: ключ
                # `ПОЛІТИКА_РЕГІСТРУ` береться саме з цього поля, а жорстке «ні» —
                # межа ЛЮДИНИ, не правило корпусу (абзац вище). Але корпус має для
                # цієї межі власний код — K-PER-05, сила `hard` «on the person's
                # authority alone», з двома дослівними прикладами («will not wear
                # wool against skin, will not wear heels»), — і доти він не стояв у
                # виході ніде. Поле `також_правила` — рівно той механізм, яким
                # система вже вимовляє «цей рядок є ще й тим правилом»
                # (K-SIL-04/07 на K-COL-01, K-KOH-04 на K-REG-01): ID доїжджає до
                # вердикту, а таблиця регістру лишається недоторканою.
                також_правила=["K-PER-05"]))

    # ── ТА САМА СЦЕНА, ЩО В СУДДІ (K-COND-04) ───────────────────────────────
    # `review` виводить відстань огляду сам і судить на ній; цей E збирається
    # ОКРЕМО і йде в крок редагування та в чеклісти. Без цього рядка вони
    # рахували б той самий образ на іншій вазі, а пункт 19 чекліста надлишку
    # («вага приобличчевих слотів ключована на відстань огляду») стояв би «без
    # входу» навіть тоді, коли нагода відстань назвала.
    import дистанція as _ДИСТ2
    _дист_образу = _ДИСТ2.з_сценарію(dict(місце=kw.get("місце"), формат=kw.get("формат"),
                                          нагода=kw.get("нагода"))).get("дистанція")
    E = O.елементи(речі, дистанція=_дист_образу)

    # K-PC-08 стоїть ПЕРШИМ і окремо: це абсолютний фільтр, і решта правил не має
    # права рахувати образ, у якому лишилась річ під вето. Порядок значущий.
    E_чисті, вето_зн = _СУД.вето_покриття(E, вето=вето_покриття, тіло=тіло)
    # `E_чисті` — це стан «у_приміщенні» (`елементи()` за замовчуванням), і стан
    # тепер їде далі: інакше BREAKS правила K-MAT-03 діяв у судді й не діяв у
    # кроці редагування, тобто одне правило давало дві різні відповіді.
    зайві, підлога, метрики = _СУД.крок_редагування(E_чисті, темп_c=kw.get("темп_c"), опади=kw.get("опади"), вітер=kw.get("вітер"), речі=речі, стан="у_приміщенні")
    # ВЕРХНІЙ ШАР ІСНУЄ ЛИШЕ НАДВОРІ (K-WEA-02): `елементи()` за замовчуванням дає стан
    # «у_приміщенні» — без пальта. Тож `верхній_шар` у ЗНІМНІ_СЛОТИ був мертвий на живому
    # шляху: крок редагування ніколи не бачив пальта (виміряно 28.08: K-CRA-04 на
    # верхньому шарі 0/200 у холодній сцені з пальтом). Тепер образ із пальтом
    # редагується і в стані «надворі», з температурою: у спеку пальто — «можна зняти»,
    # у холод його видалення робить K-WEA-01 гіршим, і крок мовчить.
    if any(r.get("слот") == "верхній_шар" for r in речі):
        E_над, _ = _СУД.вето_покриття(O.елементи(речі, стан="надворі", дистанція=_дист_образу),
                                      вето=вето_покриття, тіло=тіло)
        з2, п2, _ = _СУД.крок_редагування(E_над, темп_c=kw.get("темп_c"), опади=kw.get("опади"), вітер=kw.get("вітер"), речі=речі)
        _є = {(z["правило"], tuple(z.get("речі") or ())) for z in list(зайві) + list(підлога)}
        зайві = list(зайві) + [dict(z, стан="надворі") for z in з2 if (z["правило"], tuple(z.get("речі") or ())) not in _є]
        підлога = list(підлога) + [dict(z, стан="надворі") for z in п2 if (z["правило"], tuple(z.get("речі") or ())) not in _є]
    # K-INT-04 проактивно — на ЗІБРАНОМУ образі, не лише під час вибору (24.08.2026)
    підлога = list(підлога) + _СУД.підлога_інтересу_проактивно(E_чисті, kw.get("intent", "conventional"))
    вих["композиція"] = dict(
        жорстке_ні=зн_ні,
        вето_покриття=вето_зн,
        покриття_без_поля=_СУД.покриття_без_поля(E, тіло=тіло),
        відкриті_зони=sorted(O.відкриті_зони_образу(E_чисті, тіло=тіло)[0]),
        крок_редагування=зайві,
        підлога_інтересу=підлога,
        джерела_інтересу=_СУД.джерела_інтересу(E_чисті),
        метрики=метрики,
        тканина_проти_крою=_СУД.тканина_проти_крою(E_чисті),
        масштаби=_СУД.масштаби(E_чисті, тіло=тіло),
        порядок="K-PC-08 (вето) → K-CRA-04×K-INT-04 (редагування) → K-MAT-01 → K-SIL-06. "
                "Вето перше навмисно: решта не має рахувати образ із річчю під вето")

    # ── АКСЕСУАРНА ГІЛКА (тема-10) ───────────────────────────────────────────
