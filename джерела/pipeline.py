def пояснення_від_моделі(текст, пакет, каталог_назви=None):
    """Текст моделі крізь код: мовний гейт, речі не з образу (галюцинація), ID правил,
    покриття фактів. Повертає dict(готово, причини, покриття)."""
    import re as _re, language_gate as _МГ
    причини = []
    мова = _МГ.перевірити(текст)
    for п in (мова.get("порушення") or []):
        причини.append("мова: %s" % (п.get("суть") or п.get("правило")))
    if _re.search(r"\b[KR]-[A-Z]{2,5}-\d+", текст):
        причини.append("у тексті ID правил — людині їх не показують")
    т = текст.lower()
    в_образі = [str(r.get("назва") or "").lower() for r in пакет["речі"]]
    if каталог_назви:
        чужі = [н for н in каталог_назви if н and н.lower() not in в_образі and н.lower()[:24] in т]
        if чужі: причини.append("названо речі не з образу: %s" % ", ".join(чужі[:3]))
    покриття = []
    for ф in пакет["факти"]:
        ключі = [w for w in _re.findall(r"[а-яіїєґ']{5,}", ф["що"].lower())][:4]
        покриття.append(dict(факт=ф["що"][:60], згадано=any(k[:5] in т for k in ключі)))
    if пакет["факти"] and not any(x["згадано"] for x in покриття):
        причини.append("текст не торкається жодного факту образу")
    return dict(готово=not причини, причини=причини, покриття=покриття, мова=мова)


