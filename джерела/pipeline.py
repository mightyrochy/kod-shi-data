def діалог_від_моделі(json_моделі, текст_людини=""):
    """JSON моделі → вето / жорстке_ні / преференції у словнику коду. Значення поза
    словником не приймаються — вони йдуть у `питання_людині`, не в фільтр.
    Паралельно регекс-шлях (profile.переконання_принт) дає свій результат: де вони
    розходяться — це названо, і виграє суворіший (межа людини не губиться)."""
