def _мова_вердикту(мова):
    """`language_gate.перевірити` → `ВЕРДИКТ_V1.мова`: вирок і порушення з тим, чим
    замінити. Помилка гейта чи його відсутність — поля нема, а не «можна»."""
    if not isinstance(мова, dict) or "можна_видавати" not in мова:
        return None
    пор = []
    for п in (мова.get("порушення") or []):
        if not isinstance(п, dict) or not п.get("правило"):
            continue
        з = dict(правило=str(п["правило"]), суть=str(п.get("суть") or п["правило"]))
        зб = [str(x) for x in (п.get("збіги") or []) if x][:2]
