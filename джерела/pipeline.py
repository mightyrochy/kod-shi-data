    import composer as _КМ, graph as _ГР
    сценарій = dict(сценарій or {})
    # ДРАП ДО ГІПЕРГРАФА. `outfit.метали` і `outfit.температура_нейтралі` беруть
    # аргумент `драп`, але жоден виклик його не слав — правила вгадували метал із
    # фото там, де є пряма відповідь людини (R-PC-04: елісітація первинна).
    if драп:
        сценарій.setdefault("драп", драп)
    розбір = None
    if not ід and текст_моделі:
        розбір = ід_з_тексту(текст_моделі, кандидати=кандидати, каталог=каталог)
