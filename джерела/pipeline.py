def _шапка_вибору(образи, випадок=None, скільки_свідомих=2, кандидати=None):
    р = ["Код перевірив твої допрацьовані образи. Ось результат."]
    if випадок:
        р.append("ВИПАДОК: %s" % випадок)
    _ном = номери_речей(кандидати)[0] if (кандидати and ПАКУВАТИ_ІНДЕКСОМ) else None
    for i, о in enumerate(образи or [], 1):
        р.append("")
        р.append("── образ %d%s: %s" % (i, (" · %s" % о["підпис"]) if о.get("підпис") else "",
                                        образ_рядком(о, кандидати, _ном)))
        for с in (о.get("свідомі") or [])[:скільки_свідомих]:
            р.append("    СВІДОМО (твій оголошений хід): %s" % с)
        for б in (о.get("блокує") or [])[:4]:
            р.append("    БЛОКУЄ: %s" % (б if isinstance(б, str) else б.get("суть", б)))
        for з in (о.get("знахідки") or [])[:5]:
            р.append("    · %s%s" % ((з.get("суть") or ""),
                                     " ← оголошений хід" if з.get("свідомий") else ""))
    return р


