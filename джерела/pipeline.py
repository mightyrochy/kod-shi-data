def скелет_схеми(вузол):
    """Форма відповіді — з ТОГО САМОГО оголошення, яким її потім перевіряють.

    ЧОМУ НЕ ЗРАЗОК, ПИСАНИЙ РУКАМИ. Доти форму диктував рядок у
    `_формат_відповіді`: другий опис того, що вже оголошено у валідаторі. Вони й
    розійшлися — там `"свідомо": ["<річ> — <чому>", …]` (список РЯДКІВ), а в
    `протокол.ОБРАЗ_МОДЕЛІ` це список ОБ'ЄКТІВ `{річ, чому}`. Тобто код просив
    одне, перевіряв інше, і винною виглядала модель. Скелет рахується зі схеми,
    тож розійтися нема з чим: зміниться схема — зміниться і те, що ми просимо.
    РОЗБІР ЗА СТРУКТУРОЮ ВУЗЛА, А НЕ ЗА СЛОВОМ ТИПУ: ключі `поля`/`по_ключу`/
    `елемент` однозначні, а назви типів (`обʼєкт` з U+02BC) — рівно те місце, де
    копія в другому модулі розходиться на один невидимий символ.
    """
    в = вузол or {}
    if "поля" in в:
        return {к: скелет_схеми(з) for к, з in (в.get("поля") or {}).items()}
    if "по_ключу" in в:
        return {"<ключ>": скелет_схеми(в.get("по_ключу"))}
    if "елемент" in в:
        return [скелет_схеми(в.get("елемент"))]
    if в.get("значення"):
        return "|".join(str(x) for x in в["значення"])
    return "<%s>" % (в.get("тип") or "будь_що")


def _річ_пулу(r, ном):
    """Річ пулу об'єктом: групові ознаки стають ПОЛЯМИ речі (Т-02, крок 1).

    ПОРОЖНЄ ПОЛЕ НЕ ПИШЕТЬСЯ. `null` у кожній речі коштував би більше, ніж несе:
    «поля нема» і «поле порожнє» тут одне й те саме твердження — фід значення не
    знає. Схема (`протокол.РІЧ_ПУЛУ`) вимагає лише `н` і `назва`, решту оголошує
    необов'язковою рівно з цієї причини.
    НОМЕР — КЛЮЧ `н`, і він той самий, що бачить `ід_з_тексту`: нумерація
    роздається по ПОВНОМУ пулу (`номери_речей`), тож підмножина, пронумерована
    сама по собі, резолвилась би в іншу річ іншого магазину.
    КОЛЬОРУ ТУТ НЕМА НАВМИСНО: рядок кандидата не несе слова про колір і доти —
    його тримає фільтр палітри, крізь який пул уже пройшов. Оголосити поле й
    заповнити його hex-ом означало б дати моделі нашу внутрішню шкалу; вигадати
    слово — назвати колір, якого код не міряв.
    """
    _н = ном.get(r.get("id")) if ном else None
    річ = {"н": ("#%d·%s" % _н) if _н else str(r.get("id") or ""),
           "назва": str(r.get("назва") or "")}
    for ключ, значення in (
            # Ціна 0 — це «магазин не сказав», а не «безкоштовно»: у прозі така
            # річ ішла без ціни, і поле тут так само не з'являється.
            ("ціна", r.get("ціна") or None),
            ("тип", (r.get("тип") or r.get("тип_верхнього") or "").replace("_без_уточнення", "")),
            ("крій", r.get("крій")),
            ("гілка", r.get("гілка") or "ядро"),
            ("тканина", r.get("тканина")),
            ("матеріал", МАТЕРІАЛ_СЛОВОМ.get(r.get("матеріал"), "")),
            ("довжина", ДОВЖИНА_СЛОВОМ.get(r.get("довжина"))),
            ("рукав", r.get("рукав")),
            ("каблук", r.get("каблук")),
            ("халява", ХАЛЯВА_СЛОВОМ.get(r.get("халява"), r.get("халява"))),
            # «solid» — службове слово фіду для «без візерунка», не ознака речі.
            ("візерунок", (r.get("візерунок") if r.get("візерунок") != "solid" else None)),
            # Блиск фід міряє балом; моделі потрібен факт, а не наш бал (та сама
            # межа, що й у шапці групи: поріг 2).
            ("блиск", True if (r.get("блиск") or 0) >= 2 else None),
            ("зона", r.get("зона")),
            ("реєстр", r.get("реєстр")),
            ("схема", r.get("схема")),
            ("деталі", _деталі_речі(r)),
            ("може_стати", list(r.get("слоти_альт") or ())),
            ("є_також_у", [x for x in (r.get("також_у") or []) if x and x != "інший колір"][:3]),
    ):
        if значення not in (None, "", [], ()):
            річ[ключ] = значення
    return річ


def випадок_для_пакета(паспорт, рядок, сценарій=None, вимоги=""):
    """ВИПАДОК пакета: паспорт як він є плюс `рядок` — той самий текст, що в рук 3–4.

    ПОЛЕ, ЯКОГО НЕМА, НЕ ВИГАДУЄТЬСЯ (п. 11 СТАНДАРТУ_КОДУ). Схема
    `протокол.ВИПАДОК` вимагає лише `подія` і `рядок`; решта або має в переліку
    слово «невідомо», або чесний `null` у самому паспорті. Тому тут не дефолти, а
    ПЕРЕНОС: що паспорт знає — те й їде, і жодне слово не домальовується.
    ПЕРЕЛІК БЕРЕТЬСЯ З СХЕМИ, А НЕ ПОВТОРЮЄТЬСЯ ТУТ: значення поза enum-ом краще
    не передати зовсім, ніж підмінити сусіднім словом. Так `fashion_forward`
    (намір, якого ВИПАДОК не знає — там лише `conventional|statement`) не їде
    зовсім: намір модель і так бачить мітками гілок у пулі й дозволеним розривом.
    БЕЗ ПАСПОРТА (CLI, стенд, руки без виклику 0) `подія` збирається з нагоди й
    місця сценарію: інакше на входах без паспорта валідний пакет не склався б
    узагалі, і протокол відмовляв би половині живих шляхів.
    ВИМОГИ ЛЮДИНИ СТОЯТЬ У ВИПАДКУ, А НЕ В `завдання.вимоги`: «це частина
    випадку, а не правило коду» (`brief._вимоги`) — і старшинство над умовами
    коду в них саме тому, що вони її.
    """
    поля = _ПР.ВИПАДОК["поля"]
    в = {}
    for к, v in (паспорт or {}).items():
        if к not in поля or v in (None, "", [], {}):
            continue
        дозволені = поля[к].get("значення")
        if дозволені and v not in дозволені:
            continue
        в[к] = v
    сц = сценарій or {}
    if not str(в.get("подія") or "").strip():
        в["подія"] = ", ".join(str(сц.get(к) or "").replace("_", " ").strip()
                               for к in ("нагода", "місце")
                               if str(сц.get(к) or "").strip()) or str(рядок or "")
    в["рядок"] = str(рядок or в["подія"])
    if str(вимоги or "").strip():
        в["вимоги_людини"] = str(вимоги).strip()
    return в


def людина_для_пакета(F, тіло, палітри, гілка=None, спец=None, вибір=None):
    """ЛЮДИНА пакета: контраст, температура, палітра, тіло (`протокол.ЛЮДИНА`).

    СВІТЛОТИ ТУТ НЕМА, І ЦЕ РІШЕННЯ, А НЕ ПРОПУСК. Схема не вимагає її з тієї ж
    причини, з якої не вимагає контрасту: у світлоти рис нема СЛОВА для «входу
    нема», а поставити «середня» без виміру — маскувальний дефолт. Числа L* сюди
    теж не йдуть: це наша внутрішня шкала, і промпт від самого початку забороняє
    моделі нею говорити («не називай чисел світлоти»). Контраст, натомість, слово
    має (`палітри.контраст_рівень`) — тому він і є.
    ДЖЕРЕЛО ТЕМПЕРАТУРИ ЗВОДИТЬСЯ ДО ОДНОГО З ТРЬОХ СЛІВ, бо `palette.температура`
    віддає його цілим реченням («елісітація (золото, впевненість 0.80) — не
    залежить від камери»), а речення в полі, за яким модель приймає рішення, —
    це прози в даних. Правило переносу: була елісітація → `самозвіт`; клас
    придатний із фото → `фото`; класу нема → `утримано` і `не_стверджується`.
    АКЦЕНТИ — ЦЕ НЕЙТРАЛЬНІ КОЛЬОРИ ПАЛІТРИ НАВИВОРІТ. `палітра_практична`
    називає роль кожного кольору «нейтраль» або «колір»; хто з них буде акцентом
    у ЦЬОМУ образі, вирішує `ролі_слотів` (домінанта/секундант/акцент по слотах).
    Тому `нейтралі` — нейтралі, а `акценти` — решта палітри, тобто матеріал для
    акценту, а не призначений акцент.
    """
    л = {}
    рівень = (палітри or {}).get("контраст_рівень")
    if рівень in (_ПР.ЛЮДИНА["поля"]["контраст"].get("значення") or ()):
        л["контраст"] = рівень
    т = (палітри or {}).get("температура") or {}
    _кл = т.get("клас") if т.get("придатно") else None
    л["температура"] = {
        "клас": _кл if _кл in _ПР.ТЕМПЕРАТУРА_КЛАСИ else "не_стверджується",
        "джерело": ("самозвіт" if (т.get("елісітація") or {}).get("w") is not None
                    else "фото" if _кл else "утримано"),
    }
    розвилка = (палітри or {}).get("розвилка") or []
    _г = (розвилка[гілка] if (гілка is not None and -len(розвилка) <= гілка < len(розвилка))
          else None)
    сп = спец if isinstance(спец, dict) else ((_г or {}).get("спец") or {})
    пал = {"схема": str(сп.get("схема") or (_г or {}).get("схема") or "")}
    ролі = {с: (v or {}).get("роль") for с, v in (сп.get("слоти") or {}).items()
            if isinstance(v, dict) and v.get("роль")}
    if ролі:
        пал["ролі_слотів"] = ролі
    _кольори = ((сп.get("палітра_практична") or {}).get("кольори") or [])
    def _слова(ролі_кольору):
        вих = []
        for к in _кольори:
            if (к.get("роль") or "") not in ролі_кольору:
                continue
            с = " ".join(x for x in (к.get("назва"), к.get("hex")) if x)
            if с and с not in вих:
                вих.append(с)
        return вих
    _н = _слова(("нейтраль", "світла_нейтраль", "темна_нейтраль"))
    _а = _слова(("колір",))
    if _н: пал["нейтралі"] = _н
    if _а: пал["акценти"] = _а
    # КОЛІР, ЯКИЙ ОБРАЛА ЛЮДИНА, СТОЇТЬ У ПАЛІТРІ, А НЕ В ІНСТРУКЦІЇ. Реченням
    # («ОСНОВНИЙ КОЛІР ОБРАЗУ: … вона обрала сама») воно їде в руки 3–4, де іншого
    # каналу нема; тут канал є, і «за замовчуванням ≠ вибір» лишається видимим
    # полем `джерело`, а не прикметником у прозі.
    база = (вибір or {}).get("база")
    if база:
        пал["основа"] = {к: v for к, v in (
            ("слово", str(база).split("·")[0]),
            ("hex", (вибір or {}).get("база_hex")),
            ("джерело", ("код запропонував, вона не міняла"
                         if (вибір or {}).get("база_за_замовчуванням") else "вона обрала сама")),
        ) if v}
    л["палітра"] = пал
    тл = {}
    try:
        _зріст = float((тіло or {}).get("зріст"))
    except (TypeError, ValueError):
        _зріст = None
    if _зріст:
        тл["зріст"] = round(_зріст, 1)
    try:
        import fit as _ПС
        _з = _ПС.зони(тіло)
        тл["ярлик"] = _з.get("ярлик")
        тл["зони"] = _з.get("вектор") or {}
    except Exception:
        # Обхватів менше, ніж треба для ярлика, — це стан входу, не збій пакета:
        # `зріст` уже є, а ярлик тут не обов'язковий (див. `протокол.ЛЮДИНА`).
        pass
    л["тіло"] = тл
    return л


def пакет_для_моделі(F, каталог, тіло, слоти=("верх", "низ", "взуття", "сумка"),
                     вікна=None, сценарій=None, K=None, рез=None, варіантів=1,
                     семплер=None, рамка=None, чистити=None):
    """dict(кандидати, пакет, текст) — `текст` це ПАКЕТ_V1 у JSON, без ID правил.

    `рамка` — те в ПАКЕТ_V1, що не з пулу: `випадок`, `людина`, `правила`. Пул
    рахується тут, решту знає шов (`bridge._пакет_каталогу`), і зібрати об'єкт
    треба ДО зважування бюджету, бо бюджет міряє повний JSON, а не самий пул.
    `чистити` — функція шва, яка вирізає ID правил із рядків (`bridge._без_ід`):
    ID не забороняються моделі словами, їх просто нема чого називати.
    """
    import composer as _КМ, graph as _ГР
    сценарій = dict(сценарій or {})
    if рез is None:
        рез = _КМ.зібрати(F, каталог, вікна=вікна, тіло=тіло, слоти=слоти, **сценарій)
    if not рез.get("зібрано"):
        return dict(готово=False, чому=рез.get("чому"), кандидати={}, текст="")
    кандидати = {}
    # СЛОТИ, ЯКІ В ЦЬОМУ ПРОГОНІ СПРАВДІ Є. Мітка двослотовості («може стати також:
    # верхній_шар») має сенс лише тоді, коли той слот у цьому образі існує. Без
    # фільтра рядок кандидата підказував шар при +26 °C, де слот законно відсутній
    # (composer знімає його за температурною мапою) — тобто код кликав би людину
    # вдягнути кардиган поверх у спеку.
    _живі_слоти = set(рез.get("_кандидати") or {})
    for с, пул in (рез.get("_кандидати") or {}).items():
        рядки = []
        # ── КАП РІЖЕ ПО ГІЛКАХ, А НЕ ПЛОСКИМ ЗРІЗОМ (30.08.2026) ──────────────
        # ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after, каталог_повний, сцена «вечеря ·
        # ресторан · cocktail · statement», сід 42):
        #   before — K=20 давав ші {ядро: 20} у КОЖНОМУ слоті. Гілки стоять у
        #            хвості (ядро + межа + розрив конкатенацією), тож `пул[:20]`
        #            зрізав рівно те, заради чого сміливий намір існує: 20 речей
        #            «на межі» у верху, 20 «на межі» + 20 «розрив» у низу — усе
        #            за борт. Під statement до моделі не доходила жодна річ поза
        #            ядром палітри, тобто намір знову не мав шляху до вибору.
        #   after  — `_підпул` бере перші K КОЖНОЇ гілки: верх 20+20, низ
        #            20+20+20, взуття 20+7, сумка 20.
        # Це той самий дефект і те саме лікування, яким `_підпул` уже стереже
        # перебір композитора; у виході до ші його не стеріг ніхто.
        for r in (_КМ._підпул(пул, K) if K else пул):
            рч = _КМ._у_річ(dict(r), с, тіло)
