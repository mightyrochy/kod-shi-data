# ── ОДНЕ СЛОВО НА ОЗНАКУ — ОДИН РЕЄСТР НА ДВОХ ЧИТАЧІВ (Т-02) ────────────────
# Ці три переліки читали дві функції: шапка групи в прозовому пулі (`_поля_групи`)
# і — відколи пул став JSON-ом — поле речі (`_річ_пулу`). Доти вони жили голими
# літералами всередині `_поля_групи`. Копія в другому читачі означала б, що
# «литка» одному з них колись стане «міді», а другому лишиться «литка», і
# розійтись вони могли б мовчки: обидва рядки правильні кожен сам по собі.
ДОВЖИНА_СЛОВОМ = {"міні": "міні", "стегно": "до середини стегна", "коліно": "до коліна",
                  "литка": "міді", "максі": "максі", "талія": "до талії"}
# Основа складу → слово для моделі. Повний склад магазину («поліестер (polyester)
# - 36%…») сюди НЕ йде: він для правил, а не для запиту — див. `_КЛЮЧ_ГРУПИ`.
МАТЕРІАЛ_СЛОВОМ = {"шкір": "шкіра", "замш": "замша", "екошкір": "екошкіра",
                   "лаков": "лак", "велюр": "велюр", "нубук": "нубук"}
ХАЛЯВА_СЛОВОМ = {"щиколотка": "щиколотки", "коліно": "коліна",
                 "литка": "литки", "пах": "стегна"}


def _деталі_речі(r):
    """Деталі крою словами: прапорці фіду + те, що вивів типізатор із назви."""
    return [x for x in (("з капюшоном" if r.get("капюшон") else ""),
                        ("з поясом" if r.get("пояс") else ""),
                        ("оверсайз" if r.get("оверсайз") else ""),
                        ("стьобане" if r.get("простібка") else ""),
                        (r.get("бортність") or "")) if x] + list(r.get("деталі_крою") or [])


def _поля_групи(r, _мітка):
    м = _мітка.get(r.get("гілка") or "ядро", "")
    if "%s" in м:
        м = м % ((" (%s)" % r["схема"]) if r.get("схема") else "")
    # КАБЛУК — ОКРЕМИМ ПОЛЕМ ГРУПИ, І «НЕ ОГОЛОШЕНО» ТЕЖ ПИШЕТЬСЯ. Мовчання про
    # каблук неможливо відрізнити від «звичайного каблука», і саме в цю прогалину
    # модель вписувала «округлі скульптурні підбори» — атрибут, якого в каталозі
    # нема жодного. Порожній рядок тут був би тим самим мовчанням.
    _дов = ДОВЖИНА_СЛОВОМ.get(r.get("довжина"))
    _дет = _деталі_речі(r)
    # «сукня_без_уточнення» — службова мітка типізатора, не слово для людини чи
    # моделі; у шапці КОЖНОЇ групи суконь вона коштувала 16 символів дарма.
    return dict(тип=(r.get("тип") or r.get("тип_верхнього") or "").replace("_без_уточнення", ""),
                каблук=(r.get("каблук") or ""),
                # ── ШАПКА ГРУПИ БЕРЕ ВУЗЬКЕ СЛОВО, А НЕ ЦІЛИЙ СКЛАД ──────────
                # 11.09.2026, наслідок Н-V14-029, виміряно. `feed` тепер пише в
                # `матеріал` ЦІЛИЙ рядок складу магазину («Матеріал верху:
                # поліестер (polyester) - 36%, котон (cotton) - 61%…», до 172
                # символів) — і це правильне поле для правил, що шукають основу
                # (K-OUT-44, ВОЛОГІ_ВЕТО). Але тут поле стоїть у _КЛЮЧ_ГРУПИ, а
                # ключ групи мусить бути ГРУБИЙ: кожна нова комбінація народжує
                # окрему шапку, і бюджет символів промпту фіксований. Вимір на
                # каталог_повний: із цілим складом у ключі груп ставало
                # верхній_шар 151 → 315, верх 243 → 866, сукня 103 → 454, тобто
                # пул розсипався майже на речі, а шапка «спільних ознак» несла
                # склад однієї з них. Це ТОЙ САМИЙ дефект, який цей файл уже
                # виміряв і полагодив на реєстрах нижче (793 → 752 кандидати
                # через трійку реєстрів у ключі): матеріал для правила
                # купувався коштом самих кандидатів.
                # РІШЕННЯ: у шапку йде `волокно` — нормалізоване одне слово, яке
                # той самий `feed` уже пише поруч (V.волокно_зі_слова, найдовший
                # корінь). `матеріал` лишається запасним шляхом через ту саму
                # таблицю основ, що й доти: рука, яка пише «замш», далі бачить
                # «замша». Цілий склад нікуди не дівся — його читають правила.
                # НАСКРІЗНОГО ПРОПУСКУ РЯДКА БІЛЬШЕ НЕМА (доти тут стояло
                # `.get(…, r.get("матеріал") or "")`). До наряду ця гілка НІКОЛИ
                # не спрацьовувала: `матеріал` не писав ніхто, а сусіднє поле
                # шапки `тканина` порожнє в усіх 8 975 речах (feed пише
                # `текстура`, не `тканина`) — тобто шапка групи не несла слова
                # про тканину взагалі. Після наряду та сама гілка віддавала б у
                # КЛЮЧ ГРУПИ латинський склад цілим рядком: 640 речей із 7 193
                # мають склад, з якого `волокно_зі_слова` слова не бере («креп
                # дайвінг: viscose 65%, polyester 30%…» — латинські імена
                # волокон, яких нема у `verify.ВОЛОКНА`). Для них шапка лишається
                # такою, як була до наряду — порожньою, — і це чесніше, ніж
                # роздробити пул рядком, якого в шапці ніхто не просив.
                матеріал=(r.get("волокно")
                          or МАТЕРІАЛ_СЛОВОМ.get(r.get("матеріал"), "")),
                довжина=("довжина %s" % _дов) if _дов else "",
                візерунок=(r.get("візерунок") or "") if (r.get("візерунок") or "") != "solid" else "",
                блиск=("з блиском" if (r.get("блиск") or 0) >= 2 else ""),
                халява=("халява до %s" % ХАЛЯВА_СЛОВОМ.get(r.get("халява"), r["халява"]))
                       if r.get("халява") else "",
                деталі=" · ".join(_дет),
                крій=("крій %s" % r["крій"]) if r.get("крій") else "",
                тканина=("тканина %s" % r["тканина"]) if r.get("тканина") else "",
                зона=r.get("зона") or "",
                альт=("може стати також: %s" % ", ".join(r["слоти_альт"]))
                     if r.get("слоти_альт") else "",
                реєстр=("реєстр: %s" % r["реєстр"]) if r.get("реєстр") else "",
                мітка=м.strip(" ·"))


def номери_речей(кандидати):
    """id → (номер, код магазину). Роздача ПО ЧЕРЗІ між магазинами.

    Метод найбільшого залишку: на кожному кроці ходить магазин, у якого найбільша
    частка невиданого. Великий магазин не «доїдається» суцільним хвостом у кінці —
    він розтягується рівномірно, і сусідні номери лишаються з різних магазинів на
    всьому діапазоні, а не лише на початку."""
    # ДОДАНІ ПІД ЧАС ПЕТЛІ («потрібно» від моделі, 05.09.2026) нумеруються ПІСЛЯ всіх:
    # інакше кожне поповнення пулу зсувало б номери, і «#798·23» з попередньої
    # ітерації резолвився б в іншу річ (спіймано трасою 05.09).
    усі = [r for рч in кандидати.values() for r in рч]
    речі = [r for r in усі if not r.get("за_запитом")]
    додані = [r for r in усі if r.get("за_запитом")]
    за_маг = {}
    for r in усі:
        за_маг.setdefault((r.get("id") or "").split("@")[-1], []).append(r)
    коди = {m: "%02d" % i for i, m in enumerate(sorted(за_маг))}
    for r in додані:
        за_маг[(r.get("id") or "").split("@")[-1]].remove(r)
    за_маг = {m: v for m, v in за_маг.items() if v}
    лишок = {m: len(v) for m, v in за_маг.items()}
    курсор = {m: 0 for m in за_маг}
    всього = len(речі)
    ном, n = {}, 0
    while всього > 0:
        m = max(лишок, key=lambda k: (лишок[k] / max(1, len(за_маг[k])), лишок[k], k))
        r = за_маг[m][курсор[m]]
        курсор[m] += 1; лишок[m] -= 1; всього -= 1
        if лишок[m] <= 0:
            del лишок[m]
        n += 1
        ном[r.get("id")] = (n, коди[m])
    for r in додані:
        n += 1
        ном[r.get("id")] = (n, коди[(r.get("id") or "").split("@")[-1]])
    return ном, коди


def пакувати_кандидатів(кандидати, нумерація=None):
    """Рядки пулу: спільні поля — раз на групу, речі — коротким рядком.

    `нумерація` — (ном, коди) ПОВНОГО пулу, коли пакується його підмножина
    (02.09.2026, спіймано живою пробою `_вітрина_ремонту`): номери роздаються
    по всьому пулу, і підмножина, пронумерована окремо, показувала б моделі
    «#2·03», яке розбір резолвить у ПОВНІЙ нумерації в іншу річ іншого
    магазину — тобто кожна річ, узята з вітрини, йшла в `невірні_пари` й
    зникала з образу мовчки. Вітрина без цього була приймальнею без вітрини."""
    _мітка = {"ядро": "", "на межі": " · НА МЕЖІ палітри%s", "розрив": " · РОЗРИВ — поза палітрою"}
    ном, коди = (нумерація if нумерація is not None
                 else (номери_речей(кандидати) if ПАКУВАТИ_ІНДЕКСОМ else ({}, {})))
    рядки = []
    if кандидати.get("комплект"):
        # ЛИШЕ КОЛИ КОМПЛЕКТ Є В ПУЛІ. Рядок не має права стояти «про всяк випадок»:
        # інструкція без предмета — шум у промпті.
        рядки.append("Слот «комплект» — костюм або комплект: ЦІЛИЙ образ, верх і низ разом, "
                     "як сукня. До нього не додається ні верх, ні низ. Узяти лише половину "
                     "можна тільки з великої потреби — і тоді назви це в полі «свідомо» "
                     "свого образу.")
    if ном:
        рядки.append("Речі позначені номером і кодом магазину: «#412·29». Називай саме так — "
                     "обидві частини, інакше річ не зарахується. Магазини: "
                     + ", ".join("%s=%s" % (к, м) for м, к in sorted(коди.items(), key=lambda x: x[1])))
    for с, рч in кандидати.items():
        if not рч:
            continue          # порожній слот оголошується окремим рядком, не заголовком без речей
        групи = {}
        for r in рч:
            п = _поля_групи(r, _мітка)
            групи.setdefault(tuple(п[k] for k in _КЛЮЧ_ГРУПИ), []).append(r)
        рядки.append("· %s:" % с)
        for ключ, речі in групи.items():
            шапка = " · ".join(x for x in ключ if x)
            рядки.append("  [%s]" % шапка if шапка else "  [без ознак]")
            for r in речі:
                мітка = ("#%d·%s" % ном[r["id"]]) if ном.get(r.get("id")) else r["id"]
                ц = (" %s грн" % r["ціна"]) if r.get("ціна") else ""
                # ознаки ОДНІЄЇ речі, які не варто виносити в шапку групи
                хв = []
                if r.get("рукав"): хв.append("рукав: %s" % r["рукав"])
                if r.get("також_у"):
                    _ті = [x for x in r["також_у"] if x and x != "інший колір"][:3]
                    if _ті: хв.append("є також у: %s" % ", ".join(_ті))
                рядки.append("    %s %s%s%s" % (мітка, (r["назва"] or "")[:70], ц,
                                                (" · " + " · ".join(хв)) if хв else ""))
    return рядки



def _РЕ_кандидата(r):
    """Два-три найсильніші реєстри речі словами — для рядка кандидата.

    Числа сюди не йдуть: бал нормований усередині ОДНІЄЇ речі й між речами не
    порівнюваний, тож видавати його моделі означало б дати число, яким не можна
    користуватись. Порядок несе всю інформацію, якою можна.
    """
    try:
        import реєстри as _РЕ
        в = _РЕ.реєстр_речі(r)
        if not в.get("розпізнано"):
            return None
        # ── ПРОВІДНИЙ, А НЕ ТРІЙКА (07.09.2026, виміряно) ───────────────────
        # Спершу сюди йшли три найсильніші реєстри. Реєстр стоїть у ключі ГРУПИ,
        # і трійка роздробила пул: на `каталог_повний` кількість кандидатів упала
        # 793 → 752, бо бюджет символів фіксований, а кожна нова комбінація
        # реєстрів народжує окрему групу з власною шапкою. Тобто матеріал для
        # K-REG-01 купувався коштом самих кандидатів.
        # РІШЕННЯ: моделі йде ПРОВІДНИЙ реєстр речі — рівно те, що потрібно для
        # операції «домінанта плюс одна цитата». Повний вектор нікуди не дівся:
        # його рахує й судить код (`реєстри.перевірити`), і саме там він потрібен.
        ранг = sorted(в["бали"].items(), key=lambda x: -x[1])
        return _РЕ.РЕЄСТРИ[ранг[0][0]]["назва"].split(" / ")[0] if ранг else None
    except Exception:
        return None


