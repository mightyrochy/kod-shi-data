def паспорт_з_json(текст, сценарій, слова, вето_чипів=None):
    """JSON моделі → паспорт із дефолтами з обраного сценарію. Модель мовчить або
    бреше форматом → паспорт будується з того, що обрала людина, і це видно у `джерело`.

    ── ПАСПОРТ БЕЗ МОВЧАЗНИХ ДЕФОЛТІВ (11.09.2026, Т-09) ────────────────────────
      before — невдалий розбір мовчки віддавав дефолти сценарію: ПРИЧИНИ не лишалось
               (другій спробі нічого сказати моделі), а межі людини — `вето.зони` і
               все, що з них робить `bridge._застосувати_паспорт` (`жорстке_ні`), —
               гинули разом із відповіддю. Найсильніше, що людина сказала, не
               доїжджало до правил, і виглядало це так, ніби доїхало.
      after  — причина має ім'я (`помилка_формату`), а зони, поставлені ЧИПАМИ на
               екрані нагоди, лежать у паспорті в ОБОХ гілках і об'єднуються з тим,
               що назвала модель: обидва списки — про те, чого людина не хоче, тож
               суворіший виграє. Типи/тканини/принти/кольори лишаються каналом
               моделі (їх з тексту дістає окремий наряд Н-V07-023).
    """
    сц = dict(сценарій or {})
    _чипи = sorted({str(z).strip().lower() for z in ((вето_чипів or {}).get("зони") or [])}
                   & set(ЗОНИ_ВЕТО))
    п = dict(подія=str(слова or "").strip() or (сц.get("нагода") or ""), формат="невідомо",
             тривалість_год=None, рух="невідомо", дрес_код=сц.get("дрес_код"), ошатність=None,
             година=сц.get("година"), темп_c=сц.get("темп_c"), опади="невідомо", намір="conventional",
             бажання=[], вето=dict(типи=[], тканини=[], принти=[], кольори=[], зони=list(_чипи)),
             настрій=[], невідомо=[], джерело="плитки і чипи (модель не відповіла JSON)",
             помилка_формату=None,
             нагода=сц.get("нагода"), місце=сц.get("місце"), слова=str(слова or "").strip())
    т = str(текст or "").strip()
    об = None
    # ЧОМУ САМЕ НЕ РОЗІБРАЛОСЬ — ОКРЕМИМ ПОЛЕМ, А НЕ ЛИШЕ ФАКТОМ ПРОВАЛУ: показ
    # вкладає цей рядок у другу спробу (Н-V07-022), інакше повторний виклик просить
    # те саме тими самими словами, які вже не спрацювали.
    помилка = "порожня відповідь"
    if т:
        м = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", т, re.S)
        сир = м.group(1) if м else т[т.find("{"):т.rfind("}") + 1]
        try:
            об = _json_.loads(сир)
            помилка = None if isinstance(об, dict) else ("JSON, але не об'єкт (%s)"
                                                         % type(об).__name__)
        except Exception as e:
            об, помилка = None, "не JSON (%s)" % str(e)[:60]
    if not isinstance(об, dict):
        п["помилка_формату"] = помилка
        return п
    п["джерело"] = "модель"
    for k in ("подія", "формат", "рух", "дрес_код", "опади"):
        if об.get(k) not in (None, "", []): п[k] = str(об[k]).strip()
    for k in ("тривалість_год", "година", "темп_c"):
        try:
            if об.get(k) not in (None, ""): п[k] = float(об[k]) if k != "година" else int(об[k])
        except (TypeError, ValueError):
            pass
    if isinstance(об.get("ошатність"), (list, tuple)) and len(об["ошатність"]) == 2:
        try:
            a, b = int(об["ошатність"][0]), int(об["ошатність"][1])
            п["ошатність"] = [max(1, min(10, min(a, b))), max(1, min(10, max(a, b)))]
        except (TypeError, ValueError):
            pass
    if str(об.get("намір") or "").strip() in ("conventional", "statement"):
        п["намір"] = str(об["намір"]).strip()
    for k in ("бажання", "настрій", "невідомо"):
        if isinstance(об.get(k), list):
            п[k] = [str(x).strip() for x in об[k] if str(x).strip()][:8]
    if isinstance(об.get("вето"), dict):
        for k in п["вето"]:
            v = об["вето"].get(k)
            if isinstance(v, list): п["вето"][k] = [str(x).strip() for x in v if str(x).strip()][:8]
    # ЧИПИ НЕ СТИРАЮТЬСЯ ВІДПОВІДДЮ МОДЕЛІ. Валідний JSON без поля `вето` — не
    # заперечення межі, а мовчання про неї; доти воно затирало зони, які людина
    # поставила руками. Незнайома зона з моделі тут не відсіюється: її ще читає
    # текст вимог, а словник звіряє `bridge._застосувати_паспорт`.
    п["вето"]["зони"] = sorted({str(z).strip().lower() for z in (п["вето"].get("зони") or [])
                                if str(z).strip()} | set(_чипи))
    try:
        if об.get("ноги_вище_см") not in (None, ""): п["ноги_вище_см"] = float(об["ноги_вище_см"])
    except (TypeError, ValueError):
        pass
    return п


def паспорт_рядком(п):
    """Паспорт словами — ОДИН текст випадку для всіх чотирьох рук і шапки показу."""
    if not п:
        return ""
    р = [п.get("подія") or ""]
    # НАГОДА Й МІСЦЕ ДОЇЖДЖАЮТЬ ДО РЯДКА (11.09.2026, Т-09 крок 4). Обидва поля
    # лежали в паспорті й не виходили назовні, а цей рядок — ЄДИНИЙ текст випадку
    # для рук 3–4 і для шапки показу: «робота, офіс» перетворювалось на голі слова
    # людини, і рука без коду не знала ні нагоди, ні місця. Повтору нема: що вже
    # сказано в `подія`, вдруге не додається.
    _вжеє = str(п.get("подія") or "").lower()
    for _к in ("нагода", "місце"):
        _v = str(п.get(_к) or "").strip().replace("_", " ")
        if _v and _v.lower() not in _вжеє:
            р.append(_v); _вжеє += " " + _v.lower()
    if п.get("формат") and п["формат"] != "невідомо": р.append(п["формат"])
    if п.get("тривалість_год"): р.append("близько %g год" % float(п["тривалість_год"]))
    if п.get("рух") and п["рух"] != "невідомо": р.append(п["рух"])
    if п.get("дрес_код"): р.append("дрес-код %s" % п["дрес_код"])
    if п.get("година") is not None: р.append("%02d:00" % int(п["година"]))
    if п.get("темп_c") is not None: р.append("%g °C" % float(п["темп_c"]))
    if п.get("опади") == "так": р.append("опади")
    рядок = ", ".join(x for x in р if x)
    if п.get("бажання"): рядок += ". Хоче: " + "; ".join(п["бажання"])
    вето = [w for k in ("типи", "тканини", "принти", "кольори", "зони") for w in (п.get("вето") or {}).get(k, [])]
    if вето: рядок += ". Не хоче: " + "; ".join(вето)
    if п.get("настрій"): рядок += ". Настрій: " + ", ".join(п["настрій"])
    return рядок


