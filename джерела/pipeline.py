def діалог_від_моделі(json_моделі, текст_людини=""):
    """JSON моделі → вето / жорстке_ні / преференції у словнику коду. Значення поза
    словником не приймаються — вони йдуть у `питання_людині`, не в фільтр.
    Паралельно регекс-шлях (profile.переконання_принт) дає свій результат: де вони
    розходяться — це названо, і виграє суворіший (межа людини не губиться)."""
    import profile as _PR
    d = dict(json_моделі or {})
    вето_зони = sorted({str(z).strip().lower() for z in (d.get("вето_зони") or [])} & set(ЗОНИ_ВЕТО))
    чужі = sorted({str(z).strip().lower() for z in (d.get("вето_зони") or [])} - set(ЗОНИ_ВЕТО))
    ноги = d.get("ноги_вище_см")
    try: ноги = float(ноги) if ноги not in (None, "") else None
    except Exception: чужі.append("ноги_вище_см=%r" % (ноги,)); ноги = None
    _слова = {"смужка": ["смуж", "смуг", "полос", "stripe"], "великий принт": ["принт", "візерун", "узор"],
              "принт": ["принт", "візерун", "узор"], "блиск": ["блиск", "глянц", "паєтк", "люрекс", "атлас", "сатин"],
              "оверсайз": ["оверсайз", "oversize"], "обтисле": ["обтисл", "облягаюч", "bodycon", "skinny"]}
    жорстке = []; преф = []; невідомі = []
    for к in (d.get("не_носитиму") or []):
        к = str(к).strip().lower()
        (жорстке.extend(_слова[к]) if к in _слова else невідомі.append(к))
    for к in (d.get("не_люблю") or []):
        к = str(к).strip().lower()
        (преф.append(dict(що=к, слова=_слова[к])) if к in _слова else невідомі.append(к))
    регекс = _PR.переконання_принт(текст_людини) if текст_людини else dict(вето=[], преконання=[], преференції=[])
    # суворіший виграє: усе, що регекс визнав межею, лишається межею
    for w in регекс.get("вето") or []:
        if w not in жорстке: жорстке.append(w)
    розходження = sorted(set(регекс.get("вето") or []) - set(w for к in (d.get("не_носитиму") or []) for w in _слова.get(str(к).lower(), [])))
    return dict(вето=dict(зони=вето_зони, ноги_вище_см=ноги),
                жорстке_ні=жорстке, преференції=преф, вимоги=str(d.get("вимоги") or "").strip(),
                питання_людині=[("«%s» — не знаю такої межі; уточніть, будь ласка" % x) for x in (чужі + невідомі + list(d.get("незрозуміло") or []))],
                розходження_з_регексом=розходження,
                інструкція_моделі=регекс.get("інструкція"))


