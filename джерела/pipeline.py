# прози лишається окремим шляхом для рук без каталогу. Одна точка РОЗБОРУ тексту —
# `протокол.розібрати_json`.


def запити_речей_з_тексту(текст):
    """Прохання моделі про річ ПОЗА пулом, словами: поле `потрібно` ОБРАЗИ_V1
    (`[{слот, опис}]` або рядок), а в прозовій відповіді — рядки «ПОТРІБНО: …».
    Це право ші, про яке домовлялися: код шукає по всьому каталогу
    (`bridge.від_моделі` → `шукати_словами`).

    Поле читається ПРЯМО (Т-04): доти обʼєкт ішов крізь `_json_у_рядки`, де
    `{"слот": "шарф", "опис": "червоний шарф"}` ставав рядком `str(dict)` — і в
    пошук їхав разом із дужками й іменами полів."""
    об = _ПР.розібрати_json(текст)
    if isinstance(об, dict) and (_це_образи(об) or "потрібно" in об):
        вих = []
        for п in (об.get("потрібно") or []):
            опис = (п.get("опис") or п.get("слот")) if isinstance(п, dict) else п
            if str(опис or "").strip():
                вих.append(str(опис).strip())
        return вих[:5]
    return [м.group(1).strip() for м in
            re.finditer(r"^\s*ПОТРІБНО\s*[:：]\s*(.+)$", str(текст or ""), re.M)][:5]


