    # ЩО ЦЕ МІНЯЄ В РІШЕННІ. Обидва правила судять ОБРАЗ, і жодне не мало місця:
    # `_посадка` рахує силует по ГЕОМЕТРІЇ ТІЛА (їй потрібні виміряні краї, яких
    # фід не дає), `review` — по станах і кольору, і саме там K-SIL-09 жило за
    # гейтом площ. Тут воно судиться за СЛОТАМИ — рівно так, як його формулює
    # корпус, — а K-SIL-10 дістає першого емітента. Відро окреме від `ремесло`,
