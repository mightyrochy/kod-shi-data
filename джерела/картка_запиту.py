# -*- coding: utf-8 -*-
"""Єдиний запис фактів запиту: значення, джерело і дослівний уривок.

Картка живе всередині паспорта під ключем ``картка_запиту``. Плоскі поля —
сумісне подання для розрахунків; джерело й підтвердження читаються з картки.
"""
from copy import deepcopy
import паспорт_поля as _ПП
from паспорт_поля import чинний_ключ


# Вид факту (її слово, тлумачення, рука, типове) і його сила — лише з `паспорт_поля`.
ДЖЕРЕЛА = _ПП.ВИДИ_ФАКТУ
СИЛА = _ПП.СИЛА_ФАКТУ
СЛУЖБОВІ = frozenset(("occasion_part", "formality_branch", "formality_reason", "quotes",
                     "гілка_ошатності", "причина_ошатності", "цитати_полів")) | frozenset(
                         к for к, опис in _ПП.ПОЛЯ_ПАСПОРТА.items() if опис.get("лише_код"))
_ПОРОЖНЄ = (None, "", [], {})


def записати(паспорт, поле, значення, джерело, уривок=None, *, цитата_чинна=True, опори=()):
    """Записати один факт за R1–R4 і повернути фактичне джерело.

    Порожній або слабший запис не стирає сильнішого. Факт розмови (``her``) —
    її слово, лише коли значення дослівно стоїть у її чинному уривку
    (`паспорт_поля.вид_з_розмови`: число — цифрами); інакше — тлумачення моделі
    (``reading``) з її уривком, а без чинного уривка — без нього: значення
    зберігається, але не видається за її слово. Рівносильна новіша дія перемагає.
    ``опори`` зберігають окремі джерела частин складеного факту: уривки різних
    ходів не перетворюються на одну нібито дослівну цитату.
    """
    if поле in СЛУЖБОВІ or джерело not in ДЖЕРЕЛА:
        return None
    значення = чинний_ключ(поле, значення)
    картка = паспорт.setdefault("картка_запиту", {})
    давній = картка.get(поле) if isinstance(картка.get(поле), dict) else None
    if значення in _ПОРОЖНЄ and джерело != _ПП.РУКА:
        return давній.get("джерело") if давній else None
    # Уривок належить саме цій події розмови: невтриманий — не її; тлумачення, яке писар дав без уривка цього ходу
    # (виклик 0, давня цитата іншого значення), спирається лише на модель; рука не цитує попереднє слово.
    уривок = " ".join(str(уривок or "").split()) if цитата_чинна and джерело == _ПП.ЇЇ else ""
    if джерело == _ПП.ЇЇ:
        джерело = _ПП.вид_з_розмови(значення, уривок)
    факт = {"значення": deepcopy(значення), "джерело": джерело, "уривок": уривок}
    if опори:
        факт["опори"] = deepcopy(опори)
    if давній and _ПП.сила_факту(факт) < _ПП.сила_факту(давній):
        return _проєкція(паспорт, поле, давній)
    картка[поле] = факт
    return _проєкція(паспорт, поле, факт)


def _проєкція(паспорт, поле, факт):
    """Плоске значення й цитата — копії переможного факту, а не другий запис."""
    # Розрахунки бачать переможний факт у сумісному плоскому поданні.
    паспорт[поле] = deepcopy(факт["значення"])
    цитати = паспорт.setdefault("цитати_полів", {})
    if факт["уривок"]:
        цитати[поле] = факт["уривок"]
    else:
        цитати.pop(поле, None)
    return факт["джерело"]


def синхронізувати(паспорт, поля, *, джерела=None, уривки=None, скинуті=()):
    """Пропустити плоскі поля паспорта через одну функцію запису.

    ``джерела`` дає події поточного писаря. Без неї старий паспорт мігрується
    консервативно: розмова з уривком — ``her``, без нього — ``reading``;
    вшите значення — ``default``; позначене рукою — ``hand``.
    ``скинуті`` — поля, які писар явно зняв: їхні факти й уривки більше не чинні.
    """
    if not isinstance(паспорт, dict):
        return паспорт
    уривки = уривки if isinstance(уривки, dict) else паспорт.get("цитати_полів") or {}
    мета = паспорт.get("джерело_полів") if isinstance(паспорт.get("джерело_полів"), dict) else {}
    явні = джерела if isinstance(джерела, dict) else {}
    типові = {"form_default", "item_default"}
    for поле in СЛУЖБОВІ:
        (паспорт.get("картка_запиту") or {}).pop(поле, None)
    for поле in поля:
        if поле in скинуті:
            (паспорт.get("картка_запиту") or {}).pop(поле, None)
            (паспорт.get("цитати_полів") or {}).pop(поле, None)
            continue
        давній = факт(паспорт, поле)
        if поле not in явні and давній:
            _проєкція(паспорт, поле, давній)
            continue
        if поле in СЛУЖБОВІ or паспорт.get(поле) in _ПОРОЖНЄ:
            continue
        дж = явні.get(поле)
        автор = мета.get(поле)
        if дж not in ДЖЕРЕЛА:
            if автор in типові:
                дж = _ПП.ТИПОВЕ
            elif автор == "her":
                дж = _ПП.РУКА
            elif автор == "conversation" or поле in set(паспорт.get("поля_шару") or ()):
                дж = _ПП.ЇЇ if уривки.get(поле) else _ПП.ТЛУМАЧЕННЯ
            else:
                дж = _ПП.ЇЇ if уривки.get(поле) else _ПП.ТИПОВЕ
        записати(паспорт, поле, паспорт[поле], дж, уривки.get(поле))
    return паспорт


def завершити(паспорт, поля, *, досі=None, джерела=None, події=None):
    """Єдиний вихід писаря: відновити картку, судити нові факти й дотики.

    Плоскі поля писаря до цієї межі — кандидати. Картка попереднього
    ходу зберігається також після помилки формату; копії не ділять списків.
    """
    if isinstance(досі, dict) and isinstance(досі.get("картка_запиту"), dict):
        паспорт["картка_запиту"] = deepcopy(досі["картка_запиту"])
    синхронізувати(паспорт, поля, джерела=джерела)
    return дотики(паспорт, події)


def політика():
    """Серійний договір того самого запису для показу: сила виду й сила тлумачення з її уривком."""
    return dict(сила=dict(СИЛА), сила_з_уривком=dict(_ПП.СИЛА_З_УРИВКОМ), службові=sorted(СЛУЖБОВІ))


def факт(паспорт, поле):
    """Один факт картки або порожній словник."""
    if поле in СЛУЖБОВІ:
        return {}
    картка = паспорт.get("картка_запиту") if isinstance(паспорт, dict) else None
    return картка.get(поле, {}) if isinstance(картка, dict) else {}


def дотики(паспорт, події):
    """Застосувати явні події плиток за порядком; різниця значень не є подією."""
    for подія in події if isinstance(події, list) else ():
        if isinstance(подія, dict) and _ПП.рукою(подія) and isinstance(подія.get("поле"), str):
            записати(паспорт, подія["поле"], подія.get("значення"), _ПП.РУКА)
    return паспорт
