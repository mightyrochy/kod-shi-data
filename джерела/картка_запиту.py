# -*- coding: utf-8 -*-
"""Єдиний запис фактів запиту: значення, джерело і дослівний уривок.

Картка живе всередині паспорта під ключем ``картка_запиту``. Плоскі поля —
сумісне подання для розрахунків; джерело й підтвердження читаються з картки.
"""
import re
import unicodedata


ДЖЕРЕЛА = frozenset(("her", "hand", "reading", "default"))
СИЛА = {"default": 0, "reading": 1, "her": 2, "hand": 2}
СЛУЖБОВІ = frozenset(("occasion_part", "formality_branch", "formality_reason", "quotes",
                     "гілка_ошатності", "причина_ошатності", "цитати_полів"))
_ПОРОЖНЄ = (None, "", [], {})

# Закриті граматичні класи не несуть нового факту. Заперечення сюди не входить.
_СЛУЖБОВІ_СЛОВА = frozenset("я ти тебе тобі твій твоя твоє твої твоєї у в на до з із зі за для про о об "
                           "і й та це цей ця цю цього так".split())
_ЗАКІНЧЕННЯ = tuple(sorted(("нього", "ньої", "ньому", "ньою", "ними", "ному", "ного", "ної", "ною",
                           "ами", "ями", "ові", "еві", "ою", "ею", "єю", "ій", "ий", "ім", "их", "їх",
                           "ому", "ого", "ої", "ам", "ям", "ах", "ях", "ів", "їв", "а", "я", "у", "ю",
                           "и", "і", "ї", "е", "є", "о"), key=len, reverse=True))
_РАМКА_ПІДТВЕРДЖЕННЯ = re.compile(
    r"^(?:так[,!]?\s*)?(?:я\s+)?(?:записала|записую|занотувала|зрозуміла|підтвердила|підібрала\s+образ)\b[:,]?\s*")


_СЛОВА_ГОДИНИ = ((r"перш", 1), (r"друг", 2), (r"трет", 3), (r"четверт", 4), (r"п['’ʼ]ят", 5), (r"шост", 6),
                 (r"сьом", 7), (r"восьм", 8), (r"дев['’ʼ]ят", 9), (r"десят", 10), (r"одинадцят", 11),
                 (r"дванадцят", 12))
_ХВИЛИНИ_СЛОВАМИ = dict(enumerate(("нуль", "одна", "дві", "три", "чотири", "п'ять", "шість", "сім", "вісім", "дев'ять",
                                  "десять", "одинадцять", "дванадцять", "тринадцять", "чотирнадцять", "п'ятнадцять",
                                  "шістнадцять", "сімнадцять", "вісімнадцять", "дев'ятнадцять")))
_ХВИЛИНИ_СЛОВАМИ.update({д + о: десятки + (" " + _ХВИЛИНИ_СЛОВАМИ[о] if о else "")
                         for д, десятки in ((20, "двадцять"), (30, "тридцять"), (40, "сорок"), (50, "п'ятдесят"))
                         for о in range(10)})
_ХВИЛИНИ_ЧИСЛАМИ = {слово: число for число, слово in _ХВИЛИНИ_СЛОВАМИ.items()}
_ЧАС_СЛОВАМИ = re.compile(r"\bо\s+(?P<година>" + "|".join(к for к, _ in _СЛОВА_ГОДИНИ)
                          + r")(?:ій|ої)\s+(?:(?P<хвилини>"
                          + "|".join(re.escape(с) for с in sorted(_ХВИЛИНИ_ЧИСЛАМИ, key=len, reverse=True))
                          + r")\s+)?(?P<пора>вечора|дня|ранку|ночі)\b")


def _годинник_словами(збіг):
    """Звести явно названу порядкову годину, хвилини й пору до годинника."""
    година = next(г for корінь, г in _СЛОВА_ГОДИНИ if re.fullmatch(корінь, збіг['година']))
    година = година % 12 + (12 if збіг['пора'] in ('дня', 'вечора') else 0)
    return "%02d:%02d" % (година, _ХВИЛИНИ_ЧИСЛАМИ.get(збіг['хвилини'], 0))


def _слова_підтвердження(текст):
    """Виділити слова факту, зберігши числа, заперечення й невідомі слова.

    Відмінювання зіставляється лише через закінчення, без нечіткої схожості.
    Порядкову годину з явно названою порою зводимо до того самого годинника.
    """
    т = unicodedata.normalize("NFKC", str(текст or "")).lower().replace("’", "'").replace("ʼ", "'")
    т = _РАМКА_ПІДТВЕРДЖЕННЯ.sub("", т)
    т = _ЧАС_СЛОВАМИ.sub(_годинник_словами, т)
    # Форми тієї самої пори: прислівник, іменник та прикметник.
    т = re.sub(r"\b(?:ввечері|увечері|вечора|вечірн[а-яіїєґ]*)(?:\s+час)?\b", "вечір", т)
    т = re.sub(r"\b(сьогодні|вчора|завтра)шн[а-яіїєґ]*\b", r"\1", т)
    т = re.sub(r"\b(?:ти\s+)?(?:йдеш|ідеш)\b", "", т)
    return [с for с in re.findall(r"[+-]?\d+(?:[:.,]\d+)?|[^\W\d_]+(?:'[^\W\d_]+)*|_", т)
            if с not in _СЛУЖБОВІ_СЛОВА]


def _основа_слова(слово):
    """Зняти одне відмінкове закінчення, лишивши щонайменше три літери основи."""
    for кінець in _ЗАКІНЧЕННЯ:
        if слово.endswith(кінець) and len(слово) - len(кінець) >= 3:
            return слово[:-len(кінець)]
    return слово


def зіставити_підтвердження(текст, опори, *, мітки=()):
    """Перевірити всі слова речення проти міток, уривків і дозволеного змісту.

    Одного збігу замало: кожне додане слово мусить мати опору. Тому інше місце,
    спорідненість чи заперечення не ховаються за правильною назвою нагоди.
    Складена мітка — ціла назва: «Театр, концерт» сама не підтверджує концерт,
    якщо в її уривку лише театр. Уривок, навпаки, можна переказати частково.
    Синоніми без спільної основи консервативно лишаються непідтвердженими.
    """
    слова = _слова_підтвердження(текст)
    опорні = {с for т in опори for с in _слова_підтвердження(т)}
    основи_речення = {_основа_слова(с) for с in слова}
    for мітка in мітки:
        цілі = _слова_підтвердження(мітка)
        if цілі and all(_основа_слова(с) in основи_речення for с in цілі):
            опорні.update(цілі)
    основи = {_основа_слова(с) for с in опорні if с.isalpha()}
    чужі = [с for с in слова if с not in опорні and not (с.isalpha() and _основа_слова(с) in основи)]
    return bool(слова) and not чужі, чужі


def _число_години(значення, уривок):
    """R1: точна година є її фактом лише коли це число (цифрами чи порядковим словом: «о сьомій», «о 7 вечора» для 19,
    «на восьму») є в її уривку у формі годинника."""
    try:
        година = int(float(значення))
    except (TypeError, ValueError):
        return False
    текст = str(уривок or "").lower()
    # Цифра — година лише в формі годинника («19:30», «о 7», «на 8»): «19 жовтня» дата, не година.
    цифри = [int(x) for x in re.findall(r"(?<!\d)([01]?\d|2[0-3])\s*[:.]\s*[0-5]\d(?!\d)", текст)]
    цифри += [int(x) for x in re.findall(r"(?:^|\s)(?:о|об|на)\s+(\d{1,2})(?=\s|[,.;!?]|$)", текст)
              if int(x) <= 23]
    if any(x % 12 == година % 12 for x in цифри):
        return True
    # Слово — година лише у формі годинника: «о сьомій», «сьомої», «на восьму»; «другу» (кому) — ні.
    return any((re.search(r"(?<![а-яіїєґ'’ʼ])%s(ій|ої|ою)(?![а-яіїєґ])" % корінь, текст)
                or re.search(r"(?<![а-яіїєґ'’ʼ])на\s+%s(у|ю)(?![а-яіїєґ])" % корінь, текст)) and година in (n, n + 12)
               for корінь, n in _СЛОВА_ГОДИНИ)


def записати(паспорт, поле, значення, джерело, уривок=None, *, цитата_чинна=True):
    """Записати один факт за R1–R4 і повернути фактичне джерело.

    Порожній або слабший запис не стирає сильнішого. ``her`` без чинного
    уривка (і година без свого числа) стає ``reading``: значення зберігається,
    але не видається за її слово. Рівносильна новіша дія перемагає.
    """
    if поле in СЛУЖБОВІ or джерело not in ДЖЕРЕЛА:
        return None
    картка = паспорт.setdefault("картка_запиту", {})
    давній = картка.get(поле) if isinstance(картка.get(поле), dict) else None
    if значення in _ПОРОЖНЄ and джерело != "hand":
        return давній.get("джерело") if давній else None
    уривок = " ".join(str(уривок or "").split())
    if джерело == "her" and (not уривок or not цитата_чинна
                              or (поле == "година" and not _число_години(значення, уривок))):
        джерело = "reading"
    if давній and СИЛА[джерело] < СИЛА.get(давній.get("джерело"), -1):
        паспорт[поле] = давній.get("значення")
        return давній.get("джерело")
    факт = {"значення": значення, "джерело": джерело, "уривок": уривок}
    if not уривок and давній and давній.get("уривок"):
        факт["уривок"] = давній["уривок"]
    картка[поле] = факт
    # Розрахунки бачать переможний факт у сумісному плоскому поданні.
    паспорт[поле] = факт["значення"]
    цитати = паспорт.setdefault("цитати_полів", {})
    if факт["уривок"]:
        цитати[поле] = факт["уривок"]
    return джерело


def синхронізувати(паспорт, поля, *, джерела=None, уривки=None, скинуті=()):
    """Пропустити плоскі поля паспорта через одну функцію запису.

    ``джерела`` дає події поточного писаря. Без неї старий паспорт мігрується
    консервативно: розмова з уривком — ``her``, без нього — ``reading``;
    вшите значення — ``default``; позначене рукою — ``hand``.
    ``скинуті`` — поля, які писар явно зняв: їхні факти й уривки більше не чинні.
    """
    if not isinstance(паспорт, dict):
        return паспорт
    уривки = уривки if isinstance(уривки, dict) else паспорт.get("цитати_полів") or {}
    мета = паспорт.get("джерело_полів") if isinstance(паспорт.get("джерело_полів"), dict) else {}
    явні = джерела if isinstance(джерела, dict) else {}
    типові = {"form_default", "item_default"}
    for поле in СЛУЖБОВІ:
        (паспорт.get("картка_запиту") or {}).pop(поле, None)
    for поле in поля:
        if поле in скинуті:
            (паспорт.get("картка_запиту") or {}).pop(поле, None)
            (паспорт.get("цитати_полів") or {}).pop(поле, None)
            continue
        давній = факт(паспорт, поле)
        if поле not in явні and давній:
            паспорт[поле] = давній.get("значення")
            continue
        if поле in СЛУЖБОВІ or паспорт.get(поле) in _ПОРОЖНЄ:
            continue
        дж = явні.get(поле)
        автор = мета.get(поле)
        if дж not in ДЖЕРЕЛА:
            if автор in типові:
                дж = "default"
            elif автор == "her":
                дж = "hand"
            elif автор == "conversation" or поле in set(паспорт.get("поля_шару") or ()):
                дж = "her" if уривки.get(поле) else "reading"
            else:
                дж = "her" if уривки.get(поле) else "default"
        записати(паспорт, поле, паспорт[поле], дж, уривки.get(поле))
    return паспорт


def факт(паспорт, поле):
    """Один факт картки або порожній словник."""
    if поле in СЛУЖБОВІ:
        return {}
    картка = паспорт.get("картка_запиту") if isinstance(паспорт, dict) else None
    return картка.get(поле, {}) if isinstance(картка, dict) else {}


def дотики(паспорт, події):
    """Застосувати явні події плиток за порядком; різниця значень не є подією."""
    for подія in події if isinstance(події, list) else ():
        if isinstance(подія, dict) and подія.get("джерело") == "hand" and isinstance(подія.get("поле"), str):
            записати(паспорт, подія["поле"], подія.get("значення"), "hand")
    return паспорт
