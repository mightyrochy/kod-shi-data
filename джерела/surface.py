def слово_з_lab(lab):
    """Слово ЛЕКСИКОНУ для виміряного Lab: вікно, що ВМІЩАЄ вимір, найтісніше з таких.

    Повертає (слово, у_вікні). Коли вимір не вміщається в жодне вікно, береться
    найближче за нормованою відстанню, і `у_вікні` False — запис це показує.
    """
    L, C_, h = CS.lch(lab)
    вміщають, поруч = [], []
    for сл, (Lmin, Lmax, Cmin, Cmax, дуга) in V.ЛЕКСИКОН.items():
        if сл in V.ВІКНА_КРАМНИЦЬ:
            continue            # слово поля кольору крамниці, не слово виміру
        тісно = (Lmax - Lmin) * (Cmax - Cmin)
        у_L = Lmin <= L <= Lmax
        у_C = Cmin <= C_ <= Cmax
        у_h = True if (not дуга or C_ < 10) else V.у_дузі(h, дуга)
        if у_L and у_C and у_h:
            вміщають.append((тісно, сл))
            continue
        d = (max(0, Lmin - L) + max(0, L - Lmax)) / 10.0 + (max(0, Cmin - C_) + max(0, C_ - Cmax)) / 10.0
        if дуга and C_ >= 10 and not V.у_дузі(h, дуга):
            d += _КТ.відстань_до_дуги(h, дуга) / 30.0
        поруч.append((d, тісно, сл))
    if вміщають:
        return min(вміщають)[1], True
    return min(поруч)[2], False


def перцентиль(точки, q):
    """Лінійний перцентиль непорожньої вибірки, як у numpy."""
    return _квантиль(sorted(точки), q)


def _квантиль(с, q):
    """Лінійний перцентиль уже впорядкованої вибірки без повторного сортування."""
    t = (len(с)-1)*q/100
    i = int(t)
    return с[i]+(с[min(i+1, len(с)-1)]-с[i])*(t-i)


def _квантиль_частот(пари, q):
    """Перцентиль повторюваних значень без розгортання їхніх частот у список."""
    с = sorted(пари)
    t = (sum(n for _, n in с)-1)*q/100
    i, нак, ліва = int(t), 0, None
    for x, n in с:
        нак += n
        if ліва is None and нак > i:
            ліва = x
        if нак > i+1:
            return ліва+(x-ліва)*(t-i)
    return ліва


def середнє(точки):
    """Середня точка Lab або RGB."""
    return tuple(sum(map(itemgetter(j), точки))/len(точки) for j in range(3))


def _середнє_частот(частоти):
    """Середня точка з урахуванням кількості кожного однакового пікселя."""
    всього = sum(частоти.values())
    return tuple(sum(т[j]*n for т, n in частоти.items())/всього for j in range(3))


def _відстань(а, б):
    """Квадрат евклідової відстані без кореня."""
    return (а[0]-б[0])**2+(а[1]-б[1])**2+(а[2]-б[2])**2


def _мітка(т, центри):
    """Найближчий центр без створення лямбди для кожного пікселя."""
    найменша, мітка = float("inf"), 0
    for j, ц in enumerate(центри):
        d = math.dist(т, ц)
        if d < найменша:
            найменша, мітка = d, j
    return мітка


def _кластери_раз(точки, к, сід):
    """Один детермінований запуск k-means++ над обмеженою вибіркою."""
    if not точки:
        return [], []
    г = random.Random(сід)
    частоти = Counter(точки)
    різні = list(частоти)
    центри = [г.choice(точки)]
    відст = [float("inf")]*len(точки)
    while len(центри) < к:
        кеш = {т: _відстань(т, центри[-1]) for т in різні}
        відст = [д if д < нова else нова for д, нова in zip(відст, map(кеш.__getitem__, точки))]
        сума = sum(відст)
        if сума <= 0:
            break
        поріг, нак = г.random()*сума, 0.0
        for т, д in zip(точки, відст):
            нак += д
            if нак >= поріг:
                центри.append(т)
                break
    for _ in range(КРОКІВ):
        кеш = {т: _мітка(т, центри) for т in різні}
        групи = [{} for _ in центри]
        for т, n in частоти.items():
            групи[кеш[т]][т] = n
        нові = [_середнє_частот(гр) if гр else ц for гр, ц in zip(групи, центри)]
        зсув = max(_відстань(а, б) for а, б in zip(центри, нові))
        центри = нові
        if зсув < 1:
            break
    кеш = {т: _мітка(т, центри) for т in різні}
    return центри, [кеш[т] for т in точки]


def кластери(точки, к=6, сід=17):
    """Єдиний k-means++: найменша похибка трьох початків, як у вимірі поверхні."""
    варіанти = [_кластери_раз(точки, к, сід+i) for i in range(3)]
    return min(варіанти, key=lambda пара: sum(_відстань(т, пара[0][м]) for т, м in zip(точки, пара[1])))


def _морфологія(маска, w, h, радіус, стискати):
    """Квадратна ерозія або дилатація рядками бітів; край кадру нейтральний.

    Один байт на піксель дозволяє пакувати маску без попіксельного циклу.
    Зсуви й AND/OR виконують те саме квадратне вікно цілими рядками.
    """
    дані = bytes(маска)
    межа = int.from_bytes(b'\x01'*w, 'little')
    рядки = []
    for y in range(h):
        ряд = int.from_bytes(дані[y*w:(y+1)*w], 'little')
        новий = ряд
        for d in range(1, min(радіус, w-1)+1):
            if стискати:
                край = int.from_bytes(b'\x01'*d, 'little')
                новий &= (ряд << (8*d)) | край
                новий &= (ряд >> (8*d)) | (край << (8*(w-d)))
            else:
                новий |= (ряд << (8*d)) | (ряд >> (8*d))
        рядки.append(новий & межа)
    вих = bytearray()
    for y, ряд in enumerate(рядки):
        for yy in range(max(0, y-радіус), min(h, y+радіус+1)):
            if стискати:
                ряд &= рядки[yy]
            else:
                ряд |= рядки[yy]
        вих.extend(ряд.to_bytes(w, 'little'))
    return вих


def _плями(маска, w, h, мінімум):
    """Кількість 8-зв'язних плям після відкриття 3×3 за перетинами смуг.

    Суміжні рядки зв'язані також навскіс. Об'єднуємо цілі горизонтальні
    смуги, тому кожну внутрішню точку плями повторно не обходимо.
    """
    м = _морфологія(_морфологія(маска, w, h, 1, True), w, h, 1, False)
    батьки, площі, попередні = [], [], []

    def корінь(i):
        """Корінь смуги зі стисканням шляху."""
        while батьки[i] != i:
            батьки[i] = батьки[батьки[i]]
            i = батьки[i]
        return i

    for y in range(h):
        початок, кінець = y*w, (y+1)*w
        нинішні, p = [], 0
        while початок < кінець:
            a = м.find(b'\x01', початок, кінець)
            if a < 0:
                break
            b = м.find(b'\x00', a, кінець)
            if b < 0:
                b = кінець
            л, п = a-y*w, b-y*w
            i = len(батьки)
            батьки.append(i)
            площі.append(b-a)
            while p < len(попередні) and попередні[p][1] < л:
                p += 1
            q = p
            while q < len(попередні) and попередні[q][0] <= п:
                j = корінь(попередні[q][2])
                if j != i:
                    батьки[j] = i
                    площі[i] += площі[j]
                q += 1
            нинішні.append((л, п, i))
            початок = b
        попередні = нинішні
    return sum(п >= мінімум for i, п in enumerate(площі) if батьки[i] == i)


def поправка_тла(rgb, маска, w, h, стеля=1.25):
    """RGB та коефіцієнт експозиції за білим тлом поза маскою."""
    к = max(4, min(w, h)//40)
    край = []
    for y in range(h):
        л, п = (w, w) if y < к or y >= h-к else (min(к, w), max(к, w-к))
        for x in range(л):
            i = y*w+x
            if not маска[i]:
                край.append(rgb[i])
        for x in range(п, w):
            i = y*w+x
            if not маска[i]:
                край.append(rgb[i])
    if len(край) < 100:
        return rgb, None
    тло = tuple(перцентиль([p[j] for p in край], 50) for j in range(3))
    L, C, _ = CS.lch(CS.to_lab(tuple(int(x) for x in тло)))
    if L < 80 or C >= 8:
        return rgb, None
    п = [min(стеля, max(1, 250/max(x, 1))) for x in тло]
    канали = [[min(255, int(к*x)) for x in range(256)] for к in п]
    r, g, b = (bytes(map(itemgetter(j), rgb)).translate(bytes(канали[j])) for j in range(3))
    return list(zip(r, g, b)), round(sum(п)/3, 3)


def _точка_поверхні(частоти):
    """Колір освітленої частини й розкид поверхні без глибоких тіней і бліків."""
    світлоти = [(т[0], n) for т, n in частоти.items()]

    def смуга(lo, hi):
        """Точки між двома перцентилями світлоти."""
        a, b = _квантиль_частот(світлоти, lo), _квантиль_частот(світлоти, hi)
        с = {т: n for т, n in частоти.items() if a <= т[0] <= b}
        return с if sum(с.values()) >= 20 else частоти

    світла = смуга(50, 90)
    точка = _середнє_частот(світла)
    if math.hypot(*точка[1:]) < БЕЗБАРВНА_C:
        точка = _середнє_частот(смуга(25, 75))
    розкид = _квантиль_частот([(math.dist(т, точка), n) for т, n in частоти.items()], 75)
    розкид_ab = _квантиль_частот([(math.dist(т[1:], точка[1:]), n) for т, n in частоти.items()], 75)
    розкид_світла = _квантиль_частот([(math.dist(т[1:], точка[1:]), n) for т, n in світла.items()], 50)
    return точка, розкид, розкид_ab, (розкид_світла, _середнє_частот(світла)[0])


def _на_відрізку(м, а, б):
    """Чи точка є змішуванням двох фарб у лінійному XYZ."""
    xa, xb, xm = (CS.to_xyz(т) for т in (а, б, м))
    в = tuple(y-x for x, y in zip(xa, xb))
    дв = sum(x*x for x in в)
    if дв <= 0:
        return False
    t = sum((m-a)*v for m, a, v in zip(xm, xa, в))/дв
    return .15 < t < .85 and CS.de00(CS.from_xyz(*(a+t*v for a, v in zip(xa, в))), tuple(м)) < РІЗНИЦЯ_ОКА


def виміряти(rgb, w, h, маска, *, клас_маски, мітки_шкіри=None, шкіра_lab=None, сід=17, поправка=True):
    """RGB і маска → сегменти, розкид, придатність і пояснене «невідомо».

    Вибірка пікселів усередині ядра обмежує кластеризацію. Площа й зв'язність
    рахуються на масці. Запасна маска крамниці не має права на колір;
    рамка показу — окремий клас, її придатність вирішують позначки.
    """
    if клас_маски not in КЛАСИ_МАСКИ:
        raise ValueError("Невідомий клас маски: " + str(клас_маски))
    if w <= 0 or h <= 0 or len(rgb) != w*h or len(маска) != w*h:
        raise ValueError("Розміри RGB і маски не збігаються")
    if мітки_шкіри is not None and len(мітки_шкіри) != w*h:
        raise ValueError("Розміри міток шкіри не збігаються")
    вих = dict(сегменти=[], позначки={}, візерунок=None, придатна=False, чому="", поправка=None)
    if клас_маски == "запасна":
        вих["чому"] = ЗАПАСНА_НЕВІДОМО
        return вих
    всього = sum(маска)
    if всього < МІНІМУМ:
        вих["чому"] = "маска менша за 300 px"
        return вих
    rgb, вих["поправка"] = поправка_тла(rgb, маска, w, h) if поправка else (rgb, None)
    шк = мітки_шкіри if мітки_шкіри is not None else bytes(w*h)
    ядро = _морфологія(маска, w, h, 2, True)
    ядра = sum(ядро)
    if ядра < .5*всього:
        ядро, ядра = маска, всього
    індекси, шкіри, кліпу = [], 0, 0
    дані, початок = bytes(маска), 0
    while початок < len(дані):
        a = дані.find(b'\x01', початок)
        if a < 0:
            break
        b = дані.find(b'\x00', a)
        if b < 0:
            b = len(дані)
        for i in range(a, b):
            ш = шк[i]
            шкіри += bool(ш)
            if not ядро[i]:
                continue
            p = rgb[i]
            if p[0] >= 250 and p[1] >= 250 and p[2] >= 250:
                кліпу += 1
            elif not ш:
                індекси.append(i)
        початок = b
    позн = dict(край=round((всього-ядра)/всього, 3), шкіра=round(шкіри/всього, 3),
                кліп=round(кліпу/всього, 3), прозоре=0.0, відблиск=0.0)
    вих["позначки"] = позн
    if len(індекси) < МІНІМУМ:
        вих["чому"] = "після позначок лишилось < 300 px"
        return вих
    г = random.Random(сід)
    вибір = індекси if len(індекси) <= ВИБІРКА else sorted(г.sample(індекси, ВИБІРКА))
    кеш = {}

    def lab(i):
        """Переводить піксель у Lab з кешем повторюваних RGB."""
        p = tuple(rgb[i])
        if p not in кеш:
            кеш[p] = CS.to_lab(p)
        return кеш[p]

    точки = [lab(i) for i in вибір]
    ц, _ = кластери(точки, min(К_ПОВЕРХНІ, max(1, len(точки)//100)), сід)
    к = len(ц)
    # Вибірка визначає лише центри: площу, розкид і зв'язність рахуємо за всіма
    # пікселями маски, щоб вузький візерунок і частка придатного не губилися.
    кеш_міток = {}
    мітки_rgb = {}
    пікселі = [Counter() for _ in ц]
    частоти_rgb = Counter(map(tuple, map(rgb.__getitem__, індекси)))
    for p, кількість in частоти_rgb.items():
        if p not in кеш:
            кеш[p] = CS.to_lab(p)
        т = кеш[p]
        if т not in кеш_міток:
            кеш_міток[т] = _мітка(т, ц)
        м = кеш_міток[т]
        мітки_rgb[p] = м
        пікселі[м][т] += кількість
    n = [sum(п.values()) for п in пікселі]
    вага = 1.0
    if шкіра_lab is None and мітки_шкіри is not None:
        шк_ядро = _морфологія(шк, w, h, 2, True)
        поза = [i for i, (ш, м) in enumerate(zip(шк_ядро, маска)) if ш and not м]
        if len(поза) >= 200:
            поза = поза if len(поза) <= ВИБІРКА else г.sample(поза, ВИБІРКА)
            labs = [lab(i) for i in поза]
            шкіра_lab = tuple(перцентиль([p[j] for p in labs], 50) for j in range(3))
    схожі = [i for i in range(к) if шкіра_lab and CS.de00(ц[i], tuple(шкіра_lab)) <= ШКІРА_ДЕ]
    викл = set()
    if схожі and sum(n)-sum(n[i] for i in схожі) >= .25*sum(n):
        викл.update(схожі)
        позн["прозоре"] = round(sum(n[i] for i in схожі)*вага/всього, 3)
    групи = [[i] for i in range(к) if i not in викл and n[i]]
    if not групи:
        вих["чому"] = "усі пікселі позначені як шкіра"
        return вих

    кеш_груп, кеш_центрів = {}, {}

    def свої(гр):
        """Точні частоти всіх пікселів групи кластерів."""
        ключ = tuple(гр)
        if ключ not in кеш_груп:
            ч = Counter()
            for i in гр:
                ч.update(пікселі[i])
            кеш_груп[ключ] = ч
        return кеш_груп[ключ]

    def центр(гр):
        """Середня точка об'єднаної поверхні."""
        ключ = tuple(гр)
        if ключ not in кеш_центрів:
            кеш_центрів[ключ] = _середнє_частот(свої(гр))
        return кеш_центрів[ключ]

    def провал(а, б):
        """Чи гістограма між центрами має межу двох речовин."""
        ca, cb = центр(а), центр(б)
        в = tuple(b-a for a, b in zip(ca, cb))
        дв = sum(x*x for x in в)
        if дв < 1:
            return False
        гіст = [0]*10
        a0, a1, a2 = ca
        v0, v1, v2 = в
        for ч in (свої(а), свої(б)):
            for p, n in ч.items():
                t = sum(((p[0]-a0)*v0, (p[1]-a1)*v1, (p[2]-a2)*v2))/дв
                if 0 <= t <= 1:
                    гіст[min(9, int(t*10))] += n
        краї = min(max(гіст[:2]), max(гіст[-2:]))
        return краї > 0 and min(гіст[3:7])/краї < ПРОВАЛ

    while len(групи) > 1:
        цг = [центр(гр) for гр in групи]
        пари = sorted((CS.de00(цг[x], цг[y]), x, y) for x in range(len(групи)) for y in range(x+1, len(групи)))
        for de, x, y in пари:
            if abs(цг[x][0]-цг[y][0]) >= РОЗРИВ_СВІТЛОТИ:
                continue
            if de < РІЗНИЦЯ_ОКА or ((_одне_світло(цг[x], цг[y]) or _промінь(цг[x], цг[y])) and not провал(групи[x], групи[y])):
                групи[x] += групи.pop(y)
                break
        else:
            break
    дод = {}

    def площа(гр):
        """Площа вибірки групи."""
        return sum(n[i] for i in гр)

    while len(групи) > 2:
        цг = [центр(гр) for гр in групи]
        суміш = next(((з, x, y) for з in sorted(range(len(групи)), key=lambda i: площа(групи[i]))
                      for x in range(len(групи)) for y in range(x+1, len(групи))
                      if з not in (x, y) and min(площа(групи[x]), площа(групи[y])) > площа(групи[з])
                      and _на_відрізку(цг[з], цг[x], цг[y])), None)
        if суміш is None:
            break
        з, x, y = суміш
        ближча = x if CS.de00(цг[з], цг[x]) <= CS.de00(цг[з], цг[y]) else y
        ключ = tuple(групи[ближча])
        дод[ключ] = дод.get(ключ, 0)+площа(групи[з])
        групи.pop(з)
    позн["змішування"] = round(sum(дод.values())*вага/всього, 3)
    пов = []
    for гр in групи:
        точка, розкид, розкид_ab, світла = _точка_поверхні(свої(гр))
        пов.append(dict(кл=гр, n=(площа(гр)+дод.get(tuple(гр), 0))*вага, lab=точка,
                        розкид=розкид, розкид_ab=розкид_ab, світлота=світла[1]))
    пов.sort(key=lambda p: -p["n"])
    головна = пов[0]
    Lг, Cг, _ = CS.lch(головна["lab"])
    лишились, відбл = [головна], 0.0
    for п in пов[1:]:
        Lп, Cп, _ = CS.lch(п["lab"])
        if Lп-Lг >= 15 and Cп <= max(6, .5*Cг) and п["n"] <= ЧАСТКА_ВІДБЛИСКУ*всього:
            відбл += п["n"]
        else:
            лишились.append(п)
    позн["відблиск"] = round(відбл/всього, 3)
    корисно = sum(п["n"] for п in лишились)
    вих["придатна"] = корисно/всього >= ПРИДАТНА_ЧАСТКА
    межа_ab = max(РОЗКИД_ТОНУ, .5*CS.lch(головна["lab"])[1])
    if вих["придатна"] and (головна["розкид"] > РОЗКИД_ПОВЕРХНІ or головна["розкид_ab"] > межа_ab):
        вих["придатна"] = False
        вих["чому"] = "головна поверхня неоднорідна: розкид ΔE %.0f (межа %.0f), за тоном %.0f (межа %.0f)" % (
            головна["розкид"], РОЗКИД_ПОВЕРХНІ, головна["розкид_ab"], межа_ab)
        return вих
    if not вих["придатна"]:
        вих["чому"] = "колір речі — %.0f%% маски; решта — %s" % (100*корисно/всього, ", ".join(
            "%s %.0f%%" % (k, 100*v) for k, v in позн.items() if v >= .05))
        return вих
    карта = [-1]*(w*h)
    for i in індекси:
        карта[i] = мітки_rgb[tuple(rgb[i])]
    сег = []
    for п in лишились:
        частка = п["n"]/корисно
        if частка < МІН_ЧАСТКА_СЕГМЕНТА:
            continue
        плям = _плями([м in п["кл"] for м in карта], w, h, max(4, .002*всього))
        сл, у_вікні = слово_з_lab(tuple(п["lab"]))
        _, Cп, hп = CS.lch(п["lab"])
        нв = невизначеність_хроми(п["світлота"], п["розкид_ab"])
        сег.append(dict(слово=сл, частка=round(частка, 3), lab=[round(x, 2) for x in п["lab"]],
                        hex=CS.hex_з_lab(п["lab"]), у_вікні=у_вікні, розкид=round(п["розкид"], 1),
                        плям=плям, світлота=round(п["світлота"], 1), хрома=[round(Cп, 1), round(нв, 1)],
                        тон=round(hп) if Cп > нв else None))
        if not isinstance(сег[-1]["тон"], (int, float)):
            сег[-1]["колір_не_вимір"] = межі_сегмента(сег[-1])
    вих["сегменти"] = сег
    малюнок = [с for с in сег[1:] if с["частка"] >= ЧАСТКА_ПЛЯМ]
    вих["візерунок"] = ("принт" if any(с["плям"] >= ПЛЯМ_ПРИНТА for с in малюнок) else
                        "двоколірний" if any(с["частка"] >= ЧАСТКА_ДРУГОГО for с in малюнок) else "однотонний")
    вих["чому"] = "%s; придатна %.0f%% маски" % (вих["візерунок"], 100*корисно/всього)
    if сег and сег[0]["тон"] is None:
        вих["чому"] += "; тон невідомо: C* %.1f ≤ невизначеність %.1f (світло кадру за L* %.0f ⊕ розкид)" % (
            сег[0]["хрома"][0], сег[0]["хрома"][1], сег[0]["світлота"])
    return вих

def межі_сегмента(сегмент):
    """Частковий вимір поверхні у спільному форматі меж кольору.

    Lab лишається представником для малювання; суд читає виміряну світлоту,
    інтервал хроми C ± U та невідомий тон або його дугу, а не цю точку.
    """
    C, U = сегмент["хрома"]
    L = сегмент["lab"][0]
    тон = сегмент.get("тон")
    if isinstance(тон, (int, float)):
        тон = [тон, тон]
    return dict(свідок="partial_measure", слово=сегмент["слово"],
                вікно=[L, L, max(0.0, C-U), C+U, тон],
                чому="частковий вимір поверхні: світлота, хрома C ± U; тон невизначений")


def невизначеність_хроми(L, розкид_ab):
    """Невизначеність C* точки (одиниці a*b*): світло кадру за смугою L* ⊕ розкид освітленої частини."""
    дріж = next(д for межа, д in ДРІЖ_СВІТЛА if L < межа)
    return math.hypot(дріж, розкид_ab)


def _промінь(а, б):
    """Чи темніша з двох точок Lab — тінь світлішої: та сама фарба, менше світла (рішення 25.10, п.5).

    Тінь множить світло на число в лінійному просторі (XYZ — лінійний перетвір RGB): точки однієї
    фарби лежать на промені до чорного. Світлішу точку зсуваємо по цьому променю до світлоти темнішої
    й міряємо, що лишилось (ΔE00 < `ПРОМІНЬ_ДЕ`). Змішування двох фарб (розмиті смуги, дрібний принт)
    лежить на відрізку МІЖ ними, не на промені, тож двох кольорів воно в одну поверхню не зливає,
    хоч би й заповнило середину без провалу."""
    св, тм = (а, б) if а[0] >= б[0] else (б, а)
    X, Y, Z = CS.to_xyz(св)
    Yт = CS.to_xyz(тм)[1]
    if Y <= 0:
        return False
    к = Yт / Y
    return CS.de00(CS.from_xyz(к * X, к * Y, к * Z), tuple(тм)) < ПРОМІНЬ_ДЕ


def _одне_світло(а, б):
    """Чи дві точки Lab — та сама фарба під різним світлом (складка, тінь під рукою).

    `_тінь` порівнює хрому за однієї світлоти й при |ΔL| ≥ 30 відмовляє, а
    глибока тінь бежевого жакета на пробі темніша на 30 і НАСИЧЕНІША: у складці
    тканина світить сама на себе (міжвідбиття), тож тон лишається, а хрома
    росте. Тут: обидві точки кольорові, тон той самий (Δh < ТОН_ТІНІ), темніша
    не насиченіша за світлішу більш ніж удвічі (червоне з рожевим — два кольори,
    не тінь). Ахроматичні пари судить провал, а біле з чорним — `РОЗРИВ_СВІТЛОТИ`."""
    (L1, C1, h1), (L2, C2, h2) = CS.lch(а), CS.lch(б)
    if min(C1, C2) < БЕЗБАРВНА_C or abs(L1 - L2) >= РОЗРИВ_СВІТЛОТИ:
        return False
    if _КТ.кут(h1, h2) >= ТОН_ТІНІ:
        return False
    (Cсв, Cтем) = (C1, C2) if L1 >= L2 else (C2, C1)
    return Cтем <= 2 * Cсв + 5
