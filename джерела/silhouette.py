def відповідність(t, об, intent="conventional"):
    """K-BOD-02: чи літера образу серед цільових для літери тіла."""
    п = під_тіло(t, об, intent)
    if not п["доступно"] or п["влучає"]: return []
    if intent not in ПС.ФЛЕТЕРИНГ: return []
    # літера образу рахується з УСІЄЇ обгортки — дефолтний крій на будь-якому
    # одягненому рівні робить її здогадом, а здогад іде питанням (див. дефолтний_крій)
    заглушка = дефолтний_крій(об)
    # ── НАПРЯМ ЦІЛІ СТОЇТЬ У СУТІ, А НЕ ЛИШЕ В «ЧОМУ» ────────────────────────
    # ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026). Суть називала ДВА СТАНИ —
    # літеру тіла й літеру образу — і жодної дії. Куди вести образ, лежало в
    # `чому` й у `ремонт`, а обидва поля до ші не доходять: `bridge._стислі_знахідки`
    # лишає (правило, сила, сила_нп, суть, речі), `pipeline.промпт_ремонту` друкує
    # саму `суть` із числом.
    #   before (синтетичні образи, нагода «робота», крій оголошений):
    #     A-тіло, regular+straight  · тіло: низ ширший за плечі; образ дає: низ ширший за плечі [0.5]
    #     V-тіло, oversized+skinny  · тіло: плечі ширші за низ; образ дає: плечі ширші за низ [0.5]
    #   after:
    #     A-тіло, regular+straight  · тіло: низ ширший за плечі; образ дає: низ ширший за плечі — збалансувати верх до низу: об'єм або структура вгорі, чистий низ [0.5]
    #     V-тіло, oversized+skinny  · тіло: плечі ширші за низ; образ дає: плечі ширші за низ — пом'якшити верх, наростити низ [0.5]
    # Старий рядок недієвий буквально: у найчастішому випадку (образ повторює
    # літеру тіла) він каже те саме двічі й читається як опис, а не як зауваження;
    # ремонти ж для A і V протилежні — одному нарощувати низ, другому верх.
    # `п['чому_ціль']` — це рядок із ЦІЛЬ_ЛІТЕРИ, уже прочитаний тут-таки для
    # `чому`: жодного нового виміру, числа чи виклику для цього речення не додано.
    return [_над_дефолтним_кроєм(dict(_зн(
        "K-BOD-02", "soft",
        f"тіло: {літера_словами(п['літера_тіла'])}; образ дає: "
        f"{літера_словами(п['літера_образу'])} — {п['чому_ціль']}",
        sorted({з["носій"] for з in об if з["носій"]}),
        f"за наміром «лестити» образ веде до: {' або '.join(літера_словами(ц) for ц in п['цілі'])}. "
        f"{п['чому_ціль']}. Співвідношення тіла {п['вектор_тіла']}",
        ремонт=[f"вести образ до контуру «{літера_словами(ц)}»" for ц in п["цілі"]],
        запит=dict(чому=f"K-BOD-02: ціль «{'/'.join(п['цілі'])}»",
                   цільова_літера=п["цілі"]),
        вимір=None, поріг=None,
        ламається="мапа цілей — консенсус практиків (T3), і вона умовна на намірі: за "
                  "fashion-forward ті самі важелі інвертуються свідомо. Літера тіла "
                  "рахується з обхватів, тобто ігнорує ЛОКАЛЬНІ зони (K-BOD-00 велить "
                  "розв'язувати гібридів по зонах, а не по одній літері)"),
        # літери — для коду й вимірів (гейти, абляція), не для тексту людині
        літера_тіла=п["літера_тіла"], літера_образу=п["літера_образу"], цілі_літери=list(п["цілі"])), заглушка)]


def крої_відомі(речі):
    """K-CUT-00. Крій не вгадується з назви: доки поле не постачається, правила
    силуету стоять на дефолті «regular», і це треба знати, а не приховати."""
    без = [р["id"] for р in речі if not O.крій_речі(р)]
    невідомі = sorted({O.крій_речі(р) for р in речі
                       if O.крій_речі(р) and O.крій_речі(р) not in КРОЇ})
    if not (без or невідомі): return []
    з = _зн("K-CUT-00", "питання",
            "крій відомий не для всіх речей — форма рахується на дефолті",
            без + невідомі,
            (f"без поля «крій»: {', '.join(без)}; " if без else "")
            + (f"поза словником: {', '.join(невідомі)}" if невідомі else ""),
            примітка="постачальника поля нема: feed.py віддає сирий `параметри`, "
                     "extract.py крій не витягує. Доки так — «regular» для всіх, "
                     "тобто обгортка систематично занижує об'єм")
    з["питання_людині"] = ("Який крій у цієї речі? " + " · ".join(sorted(КРОЇ)))
    з["навіщо"] = "розблокує K-SIL-01/03 і K-BOD-02: без крою обгортка — це тіло +12%"
    з["контракт"] = dict(поле="крій", значення=sorted(КРОЇ),
                         звідки="VLM-екстракція з фото (канонічний словник, вісь "
                                "silhouette) або param розмірної сітки")
    return [з]


def перевірити(t, речі, intent="conventional", мета="лестити"):
    """Головний вхід. `речі` — та сама геометрія, що в посадка.перевірити, плюс
    поле `крій` (і, за наявності, `обхвати_виробу` з розмірної сітки)."""
    гео = [р for р in одяг_обгортки(речі)
           if р.get("верх_см") is not None and р.get("низ_см") is not None]
    if len(гео) < 2: return []
    об = обгортка(t, гео)
    return (конкуренція(t, об, intent) + об_єм(t, об, intent) +
            зонні_операції(t, об, intent) + нічия_стратегія(t, об, intent) +
            відповідність(t, об, intent) +
            крої_відомі(гео))


