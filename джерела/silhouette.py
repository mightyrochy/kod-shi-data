def під_тіло(t, об, intent="conventional"):
    """K-BOD-02 як перевірка, а не таблиця: чи літера ОБРАЗУ належить до цільових для
    літери ТІЛА.

    Літера тіла береться з посадка.зони() — торсових співвідношень (плечі:стегна, WHR),
    а НЕ з тієї самої функції, що літера образу. Це не непослідовність, а різні об'єкти:
    силует образу — це зовнішній контур від плечей до поділу, а тип тіла корпус визначає
    саме на торсі. Спроба порахувати літеру тіла обгорткою дала «V» для будь-якого тіла
    (нога звужується завжди) — тобто вимір без розрізнювальної сили."""
    з = ПС.зони(t)
    л_образу = літера(об)
    if not л_образу["доступно"]:
        return dict(доступно=False, чому=л_образу.get("чому"))
    ярлик = з["ярлик"]
    цілі, ціль_чому = ЦІЛЬ_ЛІТЕРИ.get(ярлик, ((), ""))
    # ЗБІГ ПО КОМПОНЕНТАХ, не по рядку: літера образу складена (напр. «X-A»), а цілі —
    # односкладові. Порівняння рядків давало «не влучає» для fit&flare і на A-тілі, і на
    # V-тілі одночасно — тобто для образу, який корпус радить обом.
    складові = {л_образу["тренд"], л_образу["середина"]} - {"—"}
    return dict(доступно=bool(цілі), літера_тіла=ярлик, вектор_тіла=з["вектор"],
                літера_образу=л_образу["літера"], оцінки_образу=л_образу["оцінки"],
                складові=sorted(складові),
                цілі=list(цілі), влучає=bool(складові & set(цілі)),
                чому_ціль=ціль_чому, intent_умовно=(intent in ПС.ФЛЕТЕРИНГ),
                застереження=з["застереження"])


