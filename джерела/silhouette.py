# 32 см при тілі 8 — тобто ставали НОСІЄМ обгортки, K-BOD-02 називав їх у `речі`,
# граф клав на «взуття» напругу силуету, і пакет для моделі казав «міняй взуття, бо
# боксі-крій ховає талію». Речі без поля `слот` (старі фікстури) лишаються в обгортці.
СЛОТИ_ОБГОРТКИ = ("верх", "низ", "сукня", "комплект", "верхній_шар", "колготи")

def одяг_обгортки(речі):
    """Речі, що мають право задавати ширину контуру."""
    return [р for р in речі if not р.get("слот") or р.get("слот") in СЛОТИ_ОБГОРТКИ]


def обгортка(t, речі):
    """Ширина ОБРАЗУ по всій висоті: на кожному рівні найширший із виробів, що цей
    рівень покривають. Непокриті рівні лишаються тілом — саме вони дають «відкриті
    вузькі точки» (K-FIT-06)."""
    ш_тіла = {nm: w for nm, _, w in t["профіль"]}
    дай = lambda рів: ш_тіла.get(рів)
    речі = одяг_обгортки(речі)
    out = []
    for nm, y, w_тіла in t["профіль"]:
        внески = []
        for р in речі:
            лоу, хай = min(р["верх_см"], р["низ_см"]), max(р["верх_см"], р["низ_см"])
            if not (лоу - 1e-6 <= y <= хай + 1e-6): continue
            w, дж = ширина_крою(O.крій_речі(р) or "regular", nm, дай,
                                р.get("обхвати_виробу"), t["обхвати"])
            if w is None: continue
            внески.append((w, р["id"], дж, р.get("текстура"),
                           р.get("шар") or ("верхній" if (р.get("тип") or "") in
                                            ("жакет", "пальто", "тренч", "блейзер")
                                            else "базовий"),
                           O.крій_речі(р), р.get("рід_тканини_слово")))
        if внески:
            w, хто, дж, тк, шр, кр, рс = max(внески, key=lambda v: v[0])
        else:
            w, хто, дж, тк, шр, кр, рс = w_тіла, None, "гола зона", None, "базовий", None, None
        out.append(dict(рівень=nm, см=round(y, 1), ширина_тіла=round(w_тіла, 2),
                        припуск=round(w / w_тіла, 3) if w_тіла else None,
                        джерело_припуску=дж, носій=хто,
                        # ТКАНИНА І ШАР ЇДУТЬ ДАЛІ РАЗОМ ІЗ ГЕОМЕТРІЄЮ. Без цього
                        # умова застосування мінімумів носіння («діє на полотні»,
                        # «жакет — інша колонка») лишалась би параметром, якого
                        # ніхто не постачає, тобто мертвим.
                        текстура=тк, шар=шр, крій=кр, рід_слово=рс,
                        ширина=round(w, 2), одягнено=bool(внески)))
    return out


def _на(об, рівень, поле="ширина"):
    return next((з[поле] for з in об if з["рівень"] == рівень), None)


def носії_рівнів(об, рівні):
    """Вироби, що справді вкривають ЦІ рівні.

    ЧОМУ ЦЕ ІСНУЄ (31.08.2026). Знахідки K-BOD-02, чия геометрія рахується по
    грудях/талії/стегнах, називали носіями ВСІ вироби образу — включно з тими, що
    цих рівнів не торкаються. Зміряно на каталог_повний: 17 знахідок «боксі-крій
    ховає виражену талію» адресували штани, які починаються від паху й вкривають
    лише «пах» і «коліно».
    Наслідок був не косметичний: `дефолтний_крій` шукає заглушку СЕРЕД НОСІЇВ тих
    самих трьох рівнів, а штанів там нема — тож захист «крій не оголошений →
    знахідка стає питанням» законно мовчав, і `soft`-вердикт лишався на речі, про
    яку правило нічого не міряло. Тобто адресат знахідки мусить збігатись із тим,
    що вона рахує.
    """
    return sorted({з["носій"] for з in об
                   if з.get("одягнено") and з.get("носій") and з.get("рівень") in рівні})


def дефолтний_крій(об, рівні=None):
    """Носії, чий припуск на ЦИХ рівнях стоїть на заглушці: крій не оголошений
    (обгортка взяла «regular») і розмірної сітки нема. Порожній список = припуск
    виміряний або крій названий.

    ЧОМУ ЦЕ ІСНУЄ (28.08.2026, каталог_повний, 400 знахідок K-BOD-02 із 450). У фіді
    крій є в 12 % речей, обхватів виробу — у 0. K-CUT-00 чесно казав «форма рахується
    на дефолті» як ПИТАННЯ, а K-BOD-02 поруч видавав strong-знахідку «боксі-крій ховає
    талію» з того самого «regular» — на кожній футболці, з силою 1.0. Це вимір над
    заглушкою, виданий за вимір (прецедент корпусу: K-OUT-03 над дефолтом краю виходить
    питанням із названим блокером). Правило над заглушкою не має права на регістр
    вердикту — лише на питання, яке називає, що саме треба знати."""
    return sorted({з["носій"] for з in об
                   if з["одягнено"] and з["носій"] and з.get("крій") is None
                   and not str(з.get("джерело_припуску") or "").startswith("вимір")
                   and (рівні is None or з["рівень"] in рівні)})


def _над_заглушкою(зн, носії):
    """Переводить знахідку K-BOD-02 у регістр питання, коли її геометрія стоїть на
    дефолтному крої. Суть — умовна («ЯКЩО крій прямий»), ремонт — назвати крій;
    `запит` лишається: він і є те, що правило просить у каталогу."""
    if not носії: return зн
    зн = dict(зн)
    # ті самі поля, що дає O._зн для сили «питання»: регістр, не блокує, сила з категорії
    зн["сила"] = "питання"; зн["регістр"] = O.регістр(зн["правило"], "питання")
    зн["блокує"] = False
    зн["сила_нп"], зн["сила_нп_джерело"] = O._неперервна_сила("питання")
    зн["сила_нп_джерело"] = "категорія: крій дефолтний — виміру немає"
    for k in ("впевненість", "для_стиліста", "стеля_тіру"): зн.pop(k, None)
    зн["суть"] = "ЯКЩО крій прямий (не оголошений, узято «regular»): " + зн["суть"]
    зн["чому"] = (зн.get("чому") or "") + (". Крій не відомий для: %s — припуск на цих рівнях "
                                           "стоїть на дефолті, і вердикту тут нема, є брак входу"
                                           % ", ".join(носії))
    зн["ремонт"] = ["назвати крій речі «%s» — поле `крій`" % н for н in носії]
    зн["блокер"] = "крій"; зн["питання_людині"] = ("Який крій у «%s»: прямий, приталений, "
                                                   "оверсайз, із поясом/запахом?" % "», «".join(носії))
    return зн


def ознаки(об):
    """Три ВИМІРЯНІ ознаки форми, з яких виводяться всі п'ять літер.

    ЯКОРІ ВИБРАНІ НЕ ДОВІЛЬНО, і перша спроба тут теж була хибна. Вона брала «низ» як
    ширину на НАЙНИЖЧОМУ одягненому рівні — тобто на щиколотці. Для скіні це 7 см проти
    36 см плечей, і образ «футболка + джинси» отримував виражену літеру V, якою його не
    назве жоден стиліст: дві ноги око читає як колону, а не як вістря трикутника.
    Тому нижній якір — НАЙШИРША точка нижче талії (стегно для більшості низів, поділ
    для розкльошених). Це те, що й формує нижню половину виду.

      нахил    = (низ − верх) / середня — розширення донизу (A) чи звуження (V);
      талія    = (min(верх, стегна) − талія) / середня — глибина втягнення (X);
      середина = (макс. у смузі груди–високе_стегно − max(верх, низ)) / середня — O.
    """
    одягнені = [з for з in об if з["одягнено"]]
    if len(одягнені) < 3: return None
    сер = sum(з["ширина"] for з in одягнені) / len(одягнені)
    if сер <= 0: return None
    i_талія = _ПОРЯДОК.index("талія")
    верхні = [з for з in одягнені if з["рівень"] in ("плечі", "груди")]
    нижні = [з for з in одягнені if _ПОРЯДОК.index(з["рівень"]) > i_талія]
    if not (верхні and нижні): return None
    верх = max(з["ширина"] for з in верхні)
    низ_з = max(нижні, key=lambda з: з["ширина"])
    низ = низ_з["ширина"]
    талія_ш = _на(об, "талія"); стегна_ш = _на(об, "стегна")
    смуга = [з["ширина"] for з in об
             if з["рівень"] in ("груди", "талія", "високе_стегно") and з["одягнено"]]
    return dict(
        нахил=round((низ - верх) / сер, 4),
        талія=round(((min(верх, стегна_ш) - талія_ш) / сер)
                    if (талія_ш and стегна_ш) else 0.0, 4),
        середина=round(((max(смуга) - max(верх, низ)) / сер) if смуга else 0.0, 4),
        середня_ширина=round(сер, 2), верх=round(верх, 2), низ=round(низ, 2),
        низ_на=низ_з["рівень"])


def _рампа(x, повна):
    return max(0.0, min(1.0, x / повна)) if повна else 0.0


def літера(об):
    """Літера силуету на ДВОХ ортогональних осях, а не одна з п'яти.

    ЧОМУ НЕ ОДНА. Перша версія рахувала п'ять оцінок і звала «конфліктом» малий розрив
    між першою і другою. На прогоні вона оголосила конфліктом приталений верх +
    A-line спідницю — тобто fit&flare, канонічно ВДАЛИЙ образ, у якого X і A обидві
    1.00. Правило, що спрацьовує на взірцевому образі, ловить не провал, а свою власну
    метрику. Причина: A/V/H і X/O лежать на РІЗНИХ осях. A — куди йде контур; X — чи є
    талія. «X-A» (втягнута талія + розширення донизу) — одна форма, а не дві.

      вісь тренду:   A (розширюється донизу) / V (звужується) / H (ні те, ні те)
      вісь середини: X (талія втягнута) / O (середина ширша за кінці) / — (жодного)
    """
    зн = ознаки(об)
    if зн is None:
        return dict(доступно=False, чому="менше трьох одягнених рівнів — форми нема")
    A = _рампа(зн["нахил"], C["нахил_повний"])
    V = _рампа(-зн["нахил"], C["нахил_повний"])
    X = _рампа(зн["талія"], C["талія_повна"])
    Oc = _рампа(зн["середина"], C["середина_повна"])
    тренд = "A" if A >= 0.5 else ("V" if V >= 0.5 else "H")
    середина = "X" if X >= 0.5 else ("O" if Oc >= 0.5 else "—")
    назва = (тренд if середина == "—" else
             (середина if тренд == "H" else f"{середина}-{тренд}"))
    return dict(доступно=True, літера=назва, тренд=тренд, середина=середина,
                оцінки=dict(A=round(A, 3), V=round(V, 3), X=round(X, 3), O=round(Oc, 3)),
                ознаки=зн)


def відльоти(об, поріг=None):
    """K-SIL-01, ВИМІР. Скільки разів КОНТУР образу окремо йде назовні нижче плечей.

    ДРУГА ПОМИЛКА ТУТ БУЛА ТАКА Ж ЗА ПРИРОДОЮ, ЯК ПЕРША. Спершу відльоти рахувались по
    профілю ПРИПУСКУ (ширина образу / ширина тіла). Але широка штанина має сталу ШИРИНУ
    і водночас припуск, що росте від 1.15 на стегні до 5.0 на щиколотці — просто тому,
    що нога під нею тонка. Метрика бачила там другий відліт, якого в контурі нема:
    зовні це одна пряма вертикаль. Око читає контур, а не відношення до тіла.

    Тепер рахуються виходи назовні по самій ширині: від локального мінімуму контур має
    піти назовні щонайменше на `виразність_відльоту` середньої ширини. Так рахуються і
    внутрішні опуклості (баска), і розширення до самого поділу (кльош), однаково —
    останнє в попередній версії взагалі не виявлялось, бо вершина падала на останню
    точку, а вона не мала правого сусіда."""
    поріг = C["виразність_відльоту"] if поріг is None else поріг
    i_пл = _ПОРЯДОК.index("плечі")
    ряд = [з for з in об if з["одягнено"] and _ПОРЯДОК.index(з["рівень"]) >= i_пл]
    if len(ряд) < 3: return dict(кількість=0, точки=[], контур=[], розділення=[])
    # МАСШТАБ — ВІД ТІЛА, НЕ ВІД ОБРАЗУ (виправлено після виміру). Було: середня
    # ширина ОБГОРТКИ. Наслідок: об'єм у будь-якому місці роздував знаменник і
    # РОЗБАВЛЯВ кожен інший відліт, тож із ростом баски сила K-SIL-01 падала
    # (0.74 -> 0.72 на свіпі) — правило казало, що образ стає кращим, коли другий
    # об'єм росте. Ширина тіла на тих самих рівнях від одягу не залежить, тож
    # виразність кожного відльоту тепер незалежна від об'єму сусіда.
    сер = sum(з["ширина_тіла"] for з in ряд) / len(ряд)
    сер_обгортки = sum(з["ширина"] for з in ряд) / len(ряд)
    Δ = поріг * сер
    точки, мін, вершина, у_відльоті = [], ряд[0], None, False
    долини = []            # найглибша точка між двома сусідніми відльотами
    def _закрити(вершина, мін, спад_до):
        точки.append(dict(рівень=вершина["рівень"], см=вершина["см"],
                          ширина=вершина["ширина"], носій=вершина["носій"],
                          від=мін["рівень"],
                          виразність=round((вершина["ширина"] - мін["ширина"]) / сер, 3)))
        долини.append(спад_до)
    for з in ряд[1:]:
        if not у_відльоті:
            if з["ширина"] < мін["ширина"]: мін = з
            if з["ширина"] - мін["ширина"] >= Δ:
                у_відльоті, вершина = True, з
        else:
            if з["ширина"] > вершина["ширина"]: вершина = з
            if вершина["ширина"] - з["ширина"] >= Δ:
                _закрити(вершина, мін, з)
                у_відльоті, мін = False, з
    if у_відльоті:
        точки.append(dict(рівень=вершина["рівень"], см=вершина["см"],
                          ширина=вершина["ширина"], носій=вершина["носій"],
                          від=мін["рівень"],
                          виразність=round((вершина["ширина"] - мін["ширина"]) / сер, 3)))
    # РОЗДІЛЕННЯ: глибина долини, що відокремлює відліт k від відльоту k+1.
    # Саме ця величина ПЕРЕТИНАЄ ПОРІГ у мить, коли один пік розпадається на два,
    # тобто в мить народження знахідки. Тому вона, а не виразність піка, має нести
    # силу правила: інакше правило народжується вже гучним.
    розділення = []
    for k in range(len(точки) - 1):
        долина = долини[k]["ширина"] if k < len(долини) else None
        if долина is None: continue
        глибина = min(точки[k]["ширина"], точки[k+1]["ширина"]) - долина
        розділення.append(dict(між=(точки[k]["рівень"], точки[k+1]["рівень"]),
                               долина=долини[k]["рівень"],
                               глибина=round(глибина / сер, 3)))
    return dict(кількість=len(точки), точки=точки, середня_ширина=round(сер_обгортки, 2),
                масштаб_тіла=round(сер, 2), розділення=розділення,
                контур=[(з["рівень"], з["ширина"]) for з in ряд])


