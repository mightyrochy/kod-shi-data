# ЧОМУ ЦЕ ДОДАНО. Виміряно на прогоні специфікації: згортка образу в ОДНУ літеру
# сліпне, щойно верх задає талію. Причина структурна — X стоїть у цільових літерах
# A, V і H одночасно, тож будь-який приталений верх проходив тест незалежно від
# фігури, і низ лишався необмеженим. Літера не каже, ДЕ додано ширину, а всі анти-ходи
# корпусу — саме про це.
#
# ЩО ДАЛИ ДЖЕРЕЛА ПОНАД КОРПУС (правило 1: це дельта, а не покриття).
# Корпус має ходи й анти-ходи по типах. Джерела практиків дали дві УМОВИ, яких у
# корпусі не було:
#   1. Операція над зоною ТРИСТАННА, і провал ДВОБІЧНИЙ. Було: карається тільки
#      надлишок об'єму. Стало: облягання (cling) — теж провал на широкій зоні
#      («lightweight fabrics that cling accentuate», Lamport), а намет (tent) —
#      провал з іншого боку («stiff heavy weaves tent outward»; «oversized top with
#      a flared skirt creates a tent effect»). Ціль — вузьке вікно між ними.
#   2. На ВУЗЬКІЙ зоні провал ДЗЕРКАЛЬНИЙ: недодати. Названо прямо як помилка
#      («a bottom that is too narrow does not compensate the imbalance»; «avoid skinny
#      bottoms that cling to your hips — this will make you appear top-heavy»).
#      Тобто ціль по зоні ЗНАКОВА, а не «менше об'єму — краще».
# РОДОВІД: дев'ять джерел на V-фігуру повторюють ті самі висновки; незалежних
# лінійок дві-три (Lamport / theconceptwardrobe / Arruda), решта — брендові блоги з
# комерційним інтересом саме до «неприлеглих» речей. Рахувати це як дев'ять
# підтверджень не можна, і межі вікна нижче лишаються МОЇМИ числами (T3).
# ЧОГО БРАКУЄ: усі джерела визначають вікно через ТКАНИНУ («достатня щільність»,
# «матова, що падає»), а не через припуск. Драп у системі не виміряний, тож вікно
# задане на голій геометрії — і це найімовірніше джерело хибних спрацювань.

def _смуга(дизайн_см):
    """Опублікована смуга, у яку падає дизайн-припуск (см)."""
    for назва, лоу, хай in СМУГИ:
        if дизайн_см < лоу: continue
        if хай is None or дизайн_см < хай: return назва, лоу, хай
    return СМУГИ[-1][0], СМУГИ[-1][1], None


def операція(припуск, рівень=None, обхват_тіла=None, текстура=None, шар="базовий",
             крій=None, рід=None):
    """Що річ робить із зоною — на АБСОЛЮТНІЙ осі припуску в сантиметрах обхвату.

    ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after), і це вимір, а не переказ:
      before — мітка різалась на ВІДНОШЕННІ виріб/тіло з порогами 1.00 / 1.18 / 1.25.
               Виміряно (вимір_припуску.py на медіанних грудях 92 см): `skim` тримав
               46.0% простору припуску — тобто зливав чотири опубліковані категорії
               в одну, і за критерієм §10.4 це провал (≥45%). Межа cling→skim стояла
               рівно на 0.0 см припуску, тобто код називав «ковзанням» полотняну річ,
               скроєну по обхвату тіла, яку неможливо застібнути (§17.2). Та сама
               мітка означала різне на різних тілах: skim_стеля=1.18 давала 5.7" на
               грудях 80 і 8.5" на грудях 120 — код мовчки щедрішав із розміром.
      after  — вісь у сантиметрах, різана по опублікованих смугах Threads #221, а
               нуль осі — МІНІМУМ НОСІННЯ ЦЬОГО ЛАНДМАРКА (МІН_НОСІННЯ), не тіло.
               З'являється стан `нижче_мінімуму`: річ, яку не вдягнути, більше не
               ховається всередині «cling».

    ВХІД. `припуск` — відношення ширина_виробу/ширина_тіла (те, що дає обгортка()).
    `обхват_тіла` — обхват тіла на цьому рівні в см; без нього абсолютної осі не
    існує і функція чесно повертає ВІДНОШЕННЄВИЙ фолбек, позначений `вісь="відношення"`.
    Тема-1 §10.4 велить лишити фолбек саме так: «keeping the ratio only as a fallback
    when the size chart gives no circumference».

    УМОВИ ЗАСТОСУВАННЯ (правило 2 — коли діє, наскільки, де ламається):
      · діє на ПОЛОТНІ. У трикотажі припуск є функцією розтяжності й регулярно
        від'ємний — опубліковані мінімуми там не діють узагалі (§17.1, §17.2).
        Тому при `текстура`-трикотажі стан `нижче_мінімуму` НЕ виноситься.
      · `текстура=None` — тканина невідома. Стан виноситься, але з міткою
        `умова_невідома`, і викликач зобов'язаний зрізати силу.
      · ландмарк без опублікованого мінімуму (плечі, коліно, литка) мовчить:
        `мінімум=None`, `нижче_мінімуму` неможливий.
      · верхній шар: уся таблиця підіймається на C["зсув_шару_см"] (§10.2 —
        «the whole table shifts up ¾–2" for garments worn over other garments»).
      · ЛАМАЄТЬСЯ ТАМ САМО, ДЕ Й РАНІШЕ, і §10.5 це називає: всі джерела описують
        вікно ковзання через ТКАНИНУ (щільність, драп), а не через припуск.
        Абсолютні смуги лагодять АРИФМЕТИКУ, а не залежність від тканини. Драп у
        системі не виміряний — це лишається найімовірнішим джерелом хибних спрацювань.
    """
    if припуск is None: return None
    # РІД: спершу вимір із фіду, потім дефолт крою. Крій "обидва" рід не дає — і це
    # правильно: bodycon без текстури трикотажний за конструкцією, а skinny — ні.
    # ПРІОРИТЕТ: слово назви (факт фіду про конструкцію) > ключ текстури > дефолт крою.
    рід_джерело = "слово назви (verify.рід_зі_слова)" if рід else None
    if рід is None:
        рід = рід_тканини(текстура)
        рід_джерело = "вимір (`текстура`)" if рід else None
    if рід is None and крій:
        _р = рід_за_кроєм(крій)
        if _р in ("трикотаж", "полотно"):
            рід, рід_джерело = _р, ("дефолт крою «%s» (не вимір)" % крій)
    м = МІН_НОСІННЯ.get(рівень) if рівень else None
    мін = (м or {}).get("см")
    зсув = C["зсув_шару_см"] if шар in ("верхній", "жакет", "пальто") else 0.0

    # ── фолбек: обхвату нема, абсолютної осі не існує ────────────────────────
    if обхват_тіла is None or обхват_тіла <= 0:
        назва = ("skim" if C["cling_межа"] <= припуск <= C["skim_стеля"] else
                 "cling" if припуск < C["cling_межа"] else
                 "перехід" if припуск < C["tent_межа"] else "tent")
        поза = (0.0 if назва == "skim" else
                round(C["cling_межа"] - припуск, 3) if назва == "cling" else
                round(припуск - C["skim_стеля"], 3))
        return dict(вид=назва, смуга=None, вісь="відношення", припуск=round(припуск, 3),
                    рід_тканини=рід, рід_джерело=рід_джерело,
                    поза_вікном_см=None, поза_вікном=поза,
                    чому_фолбек="обхвату тіла на рівні не передано — опубліковані смуги "
                                "стоять в абсолютних дюймах і без обхвату не рахуються "
                                "(тема-1 §10.4)")

    повний_см = обхват_тіла * (припуск - 1.0)          # см обхвату, повний припуск
    # ── нижче мінімуму носіння ───────────────────────────────────────────────
    if мін is not None and повний_см < мін - 1e-9 and рід != "трикотаж":
        return dict(
            вид="cling", смуга="нижче_мінімуму", вісь="см", припуск=round(припуск, 3),
            повний_припуск_см=round(повний_см, 1), дизайн_припуск_см=None,
            мінімум_см=мін, мінімум_джерело=м["джерело"], мінімум_нота=м["нота"],
            поза_вікном_см=round(мін - повний_см, 1),
            поза_вікном=round(мін - повний_см, 1),
            рід_тканини=рід, рід_джерело=рід_джерело, умова_невідома=(рід is None),
            чому="повний припуск %.1f см нижче опублікованого мінімуму носіння %.1f см "
                 "на рівні «%s» — полотняну річ на цьому обхваті не вдягнути. Це не "
                 "«облягає», це не носиться (тема-1 §17.2)" % (повний_см, мін, рівень),
            неоднозначність="вісь смуг прочитана як ДИЗАЙН-припуск понад мінімум "
                            "(тема-1 §17.2); конверт Big Four друкує ПОВНИЙ припуск — "
                            "розбіжність = мінімум носіння цього ландмарка")

    # ── дизайн-припуск: те, що додано понад мінімум ──────────────────────────
    база = (мін if мін is not None else 0.0) + зсув
    дизайн = повний_см - база
    назва, лоу, хай = _смуга(max(дизайн, 0.0) if дизайн >= 0 else дизайн)
    if дизайн < 0: назва, лоу, хай = "close-fitting", 0.0, СМУГИ[0][2]

    # відстань до ВІКНА КОВЗАННЯ (fitted..semifitted), у см
    вікно_лоу = next(л for н, л, _ in СМУГИ if н == СМУГИ_КОВЗАННЯ[0])
    вікно_хай = next(х for н, _, х in СМУГИ if н == СМУГИ_КОВЗАННЯ[-1])
    поза = (0.0 if назва in СМУГИ_КОВЗАННЯ else
            round(вікно_лоу - дизайн, 1) if дизайн < вікно_лоу else
            round(дизайн - вікно_хай, 1))

    return dict(
        вид=СМУГА_У_ВИД[назва], смуга=назва, вісь="см", припуск=round(припуск, 3),
        повний_припуск_см=round(повний_см, 1), дизайн_припуск_см=round(дизайн, 1),
        мінімум_см=мін, мінімум_джерело=(м or {}).get("джерело"),
        мінімум_нота=(м or {}).get("нота"),
        зсув_шару_см=(зсув or None), поза_вікном_см=поза, поза_вікном=поза,
        рід_тканини=рід, рід_джерело=рід_джерело,
        умова_невідома=(рід is None and мін is not None),
        смуга_межі=(лоу, хай),
        чому=("повний припуск %.1f см; мінімум носіння %s → дизайн-припуск %.1f см "
              "= смуга «%s» (Threads #221). Вікно рівної лінії — %s: %.1f–%.1f см"
              % (повний_см, ("%.1f см (%s)" % (мін, (м or {}).get("джерело")))
                 if мін is not None else "не опубліковано для цього рівня",
                 дизайн, назва, "/".join(СМУГИ_КОВЗАННЯ), вікно_лоу, вікно_хай)),
        неоднозначність="вісь смуг прочитана як ДИЗАЙН-припуск понад мінімум "
                        "(тема-1 §17.2); конверт Big Four друкує ПОВНИЙ припуск — "
                        "розбіжність = мінімум носіння цього ландмарка")


ЗОНИ_ПАРИ = dict(верх=("плечі", "груди"), низ=("високе_стегно", "стегна"))


def ролі_зон(t):
    """Роль кожної зони НА ЦЬОМУ ТІЛІ: широка / вузька / нейтральна.
    Рахується з балансної пари (верх проти стегон), а не з ярлика типу — саме цього
    вимагає K-BOD-00 і саме це дає розрізнення там, де літера сліпла.

    ВИСОКЕ СТЕГНО ПРИДУШЕНЕ, КОЛИ ВОНО НЕ ВИМІРЯНЕ (тема-1 §17.3). Доти воно
    діставало роль стегна — тобто дефект `високе_стегно = стегна × 0.92` із areas
    проліз сюди й зробив вигляд, ніби зона має власний сигнал. Насправді при
    похідному значенні роль високого стегна є АЛГЕБРАЇЧНОЮ ТІНЮ ролі стегна, і будь-яка
    знахідка на ній — подвійний рахунок того самого виміру. Тепер зона мовчить
    (`роль=None`), а причина їде в `придушено`."""
    о = t["обхвати"]
    верх_о, низ_о = max(о["плечі"], о["груди"]), о["стегна"]
    δ = ((низ_о - верх_о) / верх_о) if верх_о else 0.0
    поріг = C["перекос_пари"]
    if δ >= поріг:      ролі = dict(верх="вузька", низ="широка")
    elif δ <= -поріг:   ролі = dict(верх="широка", низ="вузька")
    else:               ролі = dict(верх="нейтральна", низ="нейтральна")
    whr = о["талія"] / о["стегна"]
    out = {}
    for пара, зони_ in ЗОНИ_ПАРИ.items():
        for z in зони_: out[z] = ролі[пара]
    # ЧИТАЄТЬСЯ З ПОСАДКИ, не копіюється: до цього те саме 0.78 стояло голим
    # тут і в посадка.зони, без жодного коментаря, що це одне число. Гейт
    # двійників C такі копії не бачить — він шукає ОБІЦЯНКУ «та сама, що в X»,
    # а мовчазний двійник її не дає. Саме тому мовчазний і небезпечніший.
    out["талія"] = ("виражена" if whr <= ПС.C["whr_виражена"] else "невиражена")
    пров = ПС.areas.провенанс_високого_стегна(о)
    придушено = []
    if not пров["вимір"]:
        out["високе_стегно"] = None
        придушено.append(dict(зона="високе_стегно", чому=пров["чому"],
                              як_зняти=пров["як_зняти"]))
    return dict(ролі=out, перекос=round(δ, 3), WHR=round(whr, 3),
                балансна_пара=dict(верх=верх_о, низ=низ_о),
                придушено=придушено)


# Ціль по ролі зони за наміром «лестити». ЗНАКОВА: на широкій зоні провал двобічний,
# на вузькій — однобічний (недодати). Це і є мапа K-BOD-02, перекладена на зони.
ЦІЛЬ_ЗОНИ = {
 "широка":  dict(ціль="skim", погано=("cling", "tent"),
                 чому="широка зона: облягання простежує її, намет робить її ще ширшою; "
                      "робоче — рівне ковзання"),
 "вузька":  dict(ціль="об'єм", погано=("cling",),
                 чому="вузька зона балансної пари: облягання не компенсує перекіс і "
                      "робить протилежну зону ще помітнішою"),
 "нейтральна": dict(ціль=None, погано=(),
                    чому="перекос пари нижчий за поріг — сигналу нема"),
}


def зонні_операції(t, об, intent="conventional"):
    """K-BOD-02 по зонах. Одна знахідка = одна зона, де операція суперечить ролі."""
    if intent not in ПС.ФЛЕТЕРИНГ: return []
    р = ролі_зон(t)
    зн = []
    for з in об:
        z = з["рівень"]
        роль = р["ролі"].get(z)
        if роль not in ЦІЛЬ_ЗОНИ or not з["одягнено"]: continue
        ц = ЦІЛЬ_ЗОНИ[роль]
        оп = операція(з["припуск"], рівень=z, обхват_тіла=(t["обхвати"] or {}).get(z),
                      текстура=з.get("текстура"), шар=з.get("шар", "базовий"),
                      крій=з.get("крій"), рід=з.get("рід_слово"))
        if not оп: continue
        # припуск цієї зони стоїть на дефолтному крої → знахідка нижче виходить питанням
        заглушка_зони = дефолтний_крій([з])
        # НИЖЧЕ МІНІМУМУ — окрема знахідка, і вона НЕ про лестити. Річ, яку не вдягнути,
        # є дефектом на будь-якій зоні й за будь-якого наміру; доти вона ховалась
        # усередині «cling» і в нейтральній зоні мовчала зовсім.
        if оп.get("смуга") == "нижче_мінімуму":
            # ТКАНИНА НЕ ВІДОМА -> ПИТАННЯ, НЕ ВЕРДИКТ. Умова застосування мінімумів —
            # полотно; у трикотажі припуск регулярно від'ємний і правило не діє зовсім
            # (тема-1 §17.1). Тобто на невідомій тканині ця геометрія не є дефектом —
            # вона є НЕВІДОМІСТЮ, і єдиний чесний вихід — спитати. Доти невідома
            # тканина йшла тим самим текстом, що й виміряне полотно.
            невідомо = оп.get("умова_невідома")
            зн.append(_зн(
                "K-BOD-02", "питання" if невідомо else "strong",
                (f"«{з['носій']}» на «{z}»: нижче мінімуму носіння ЯКЩО це полотно"
                 if невідомо else
                 f"«{з['носій']}» на рівні «{z}» — нижче мінімуму носіння"),
                [з["носій"]], оп["чому"] +
                (". Тканина не відома. У трикотажі опублікований мінімум не діє взагалі "
                 "(припуск є функцією розтяжності й регулярно від'ємний), тож на цій "
                 "геометрії вердикту нема — є брак входу"
                 if невідомо else ""),
                ремонт=([f"назвати тканину речі «{з['носій']}» (полотно / трикотаж) — "
                         f"поле `текстура`"] if невідомо else
                        [f"розмір більший або крій із припуском ≥ {оп['мінімум_см']} см "
                         f"на «{z}»"]),
                запит=dict(слот=None, замість=з["носій"], зона=z,
                           припуск_від_см=оп["мінімум_см"],
                           чому=f"мінімум носіння Threads #221 на «{z}»"),
                вимір=оп["поза_вікном_см"], поріг=0.0, повна=C["повна_операції_см"],
                примітка=оп.get("неоднозначність"),
                ламається="мінімуми опубліковані для ПОЛОТНА; у трикотажі припуск є "
                          "функцією розтяжності й регулярно від'ємний — там правило не "
                          "діє. Родовід одноголосий (Threads = конверти Big Four), T3"))
            зн[-1] = _над_заглушкою(зн[-1], заглушка_зони)
            continue
        if оп["вид"] not in ц["погано"]: continue
        _вік = "%s–%s см дизайн-припуску" % (СМУГИ[1][1], СМУГИ[2][2])
        зн.append(_зн(
            "K-BOD-02", "strong",
            f"зона «{z}» ({роль}) — річ «{з['носій']}» її {'обляга' if оп['вид']=='cling' else 'накриває наметом'}",
            [з["носій"]],
            (f"{оп['чому']}. Вихід за вікно {оп['поза_вікном_см']} см. "
             if оп["вісь"] == "см" else
             f"припуск {оп['припуск']} (вісь відношень, фолбек: {оп['чому_фолбек']}). ")
            + f"{ц['чому']}. Балансна пара: верх {р['балансна_пара']['верх']} см, "
              f"низ {р['балансна_пара']['низ']} см, перекос {р['перекос']:+.1%}",
            ремонт=([f"крій, що ковзає по «{z}»: {_вік}"] if роль == "широка" else
                    [f"крій, що додає об'єм на «{z}»"]),
            запит=dict(слот=None, замість=з["носій"], зона=z,
                       дизайн_припуск_від_см=(СМУГИ[1][1] if роль == "широка"
                                              else СМУГИ[2][2]),
                       дизайн_припуск_до_см=(СМУГИ[2][2] if роль == "широка" else None),
                       чому=f"K-BOD-02 по зоні «{z}» ({роль})"),
            вимір=оп["поза_вікном"], поріг=0.0,
            повна=(C["повна_операції_см"] if оп["вісь"] == "см"
                   else C["повна_операції"]),
            примітка=оп.get("неоднозначність"),
            ламається="смуги лагодять АРИФМЕТИКУ, не залежність від тканини (тема-1 "
                      "§10.5): всі джерела описують вікно ковзання через щільність і "
                      "драп, а не через припуск. Жорстке полотно ставить намет за "
                      "меншого припуску, м'яке обляга за більшого. Драп не виміряний — "
                      "це лишається найімовірнішим джерелом хибних спрацювань"))
        зн[-1] = _над_заглушкою(зн[-1], заглушка_зони)
    return зн


def нічия_стратегія(t, об, intent="conventional"):
    """K-BOD-02 для H/нейтральної пари. Корпус тут вимогливіший, ніж до інших типів, і
    вимога СИНГУЛЯРНА: «створити талію АБО свідома колона — одна зі стратегій
    ОБОВ'ЯЗКОВА; нічия стратегія читається як мішок». Це єдиний тип, де відсутність
    ходу сама є провалом, — і саме тому зонні ролі тут мовчать: перекосу пари нема,
    карати нема що. Виміряно: без цього правила H пропускав 42% простору кроїв проти
    19% в A — тобто для найпоширенішої фігури фільтр не працював зовсім.

    Обидві стратегії вимірні на обгортці:
      талія  — припуск на талії помітно менший за припуск на грудях і на стегнах;
      колона — усі одягнені рівні тримаються у вузькій смузі припуску (рівна лінія).
    """
    if intent not in ПС.ФЛЕТЕРИНГ: return []
    р = ролі_зон(t)
    if р["ролі"].get("стегна") != "нейтральна": return []
    # ЗНАЙДЕНО НА ПРОГОНІ: гейт стояв тільки на нейтральній парі, а її мають і H, і X
    # (у обох плечі ≈ стегна). Тому X — тіло, у якого талія Є, — діставало вимогу,
    # адресовану H, і в нього відпадав `belted`, тобто його ж канонічний хід.
    # Вимога «створити талію або колону» стосується тіла, яке талії НЕ дає.
    # Для тіла з вираженою талією корпус вимагає протилежного: не сховати лінію.
    виражена = р["ролі"].get("талія") == "виражена"
    тал = _на(об, "талія", "припуск")
    гр = _на(об, "груди", "припуск"); ст = _на(об, "стегна", "припуск")
    if тал is None or гр is None or ст is None: return []
    втягнення = min(гр, ст) - тал
    прип = [з["припуск"] for з in об if з["одягнено"] and з["припуск"] is not None]
    смуга = (max(прип) - min(прип)) if прип else 0.0
    # Рівні, на яких стоїть вимір: груди/талія/стегна. Носій із дефолтним кроєм на
    # будь-якому з них переводить знахідку в питання (див. дефолтний_крій).
    заглушка = дефолтний_крій(об, ("груди", "талія", "стегна"))
    if виражена:
        # X: «слідувати лінії». Провал — коли одяг ЗАПОВНЮЄ талію: припуск на талії не
        # менший за припуск на грудях і стегнах, тобто вигин тіла зникає під річчю.
        if втягнення >= 0.0: return []
        return [_над_заглушкою(_зн(
            "K-BOD-02", "strong",
            "боксі-крій ховає виражену талію",
            носії_рівнів(об, ("груди", "талія", "стегна")),
            # ЗНАЙДЕНО МОВНИМ ГЕЙТОМ НА ВЛАСНОМУ ВИХОДІ: тут у текст, що йде ЛЮДИНІ,
            # їхало сире WHR. Два окремі порушення в одному рядку:
            #   1) R-BPC-02 / R-LNG-01 — коментар про тіло числом. Показати людині
            #      «ваш WHR 0.70» — той самий жанр, що «вам краще L»: пояснення має
            #      триматись композиції, не метрики тіла.
            #   2) на цьому тілі WHR вийшов рівно 0.70, тобто текст ще й ЛУНАВ як
            #      фольклорний «ідеальний» коефіцієнт (R-ABC-13), якого система не
            #      має права ні стверджувати, ні натякати.
            # Число нікуди не зникло — воно поїхало в `діагностика`, яку читає розробник
            # і не читає людина.
            f"тіло дає виражену талію, але припуск на талії {тал} НЕ менший за "
            f"груди {гр} і стегна {ст} — вигин зникає під річчю (втягнення {втягнення:+.3f})",
            ремонт=["крій, що йде за лінією: приталений, запах, футляр, з поясом",
                    "АБО свідомо інша форма — але тоді це вибір, а не дефолт"],
            запит=dict(слот="верх", крій=["fitted", "wrap", "belted", "sheath", "bodycon"],
                       чому="K-BOD-02: не ховати виражену талію"),
            вимір=abs(втягнення), поріг=0.0, повна=C["втягнення_H"],
            ламається="міряється лише геометрія: талію видно й крізь прямий крій, якщо "
                      "тканина падає, а пояс носиться поверх — цього модуль не бачить",
            діагностика=dict(WHR=р["WHR"], перекос=р["перекос"],
                             нота="метрики тіла для розробника; у текст людині не йдуть "
                                  "(R-LNG-01, R-BPC-02)")), заглушка)]
    є_талія = втягнення >= C["втягнення_H"]
    є_колона = смуга <= C["смуга_колони"]
    if є_талія or є_колона: return []
    return [_над_заглушкою(_зн(
        "K-BOD-02", "strong",
        "ні талії, ні колони — «нічия» стратегія",
        носії_рівнів(об, ("груди", "талія", "стегна")),
        f"втягнення талії {втягнення:+.3f} при потрібних {C['втягнення_H']} "
        f"(припуск: груди {гр}, талія {тал}, стегна {ст}); смуга припусків по образу "
        f"{смуга:.3f} при потрібних ≤{C['смуга_колони']} для читабельної колони. "
        f"Перекос балансної пари {р['перекос']:+.1%} — тіло не дає сигналу, тож форму "
        f"мусить задати одяг",
        ремонт=["створити талію: пояс, запах, баска, приталений крій",
                "АБО свідома колона: рівна лінія без перепадів (шифт, лонглайн-шар)"],
        запит=dict(слот="верх", крій=["belted", "wrap", "peplum", "fitted", "shift"],
                   чому="K-BOD-02: одна зі стратегій обов'язкова"),
        вимір=max(0.0, C["втягнення_H"] - втягнення), поріг=0.0,
        повна=C["втягнення_H"],
        ламається="дві стратегії взаємно виключні за побудовою тесту, а в реальному "
                  "образі бувають проміжні стани (легка талія + майже колона); поріг "
                  "втягнення не калібрований"), заглушка)]


