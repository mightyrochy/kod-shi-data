    # прийомом, яким сюди їдуть команди верхнього шару й `вих["акцент"]`.
    # ── ПІДСУМОК ДВОБІЧНОЇ МОДЕЛІ ЯКОСТІ (K-SYS-08/09) — У ЧЕКЛІСТІ, НЕ ЗНАХІДКОЮ ──
