# Прийоми, що рахують лише кольорові речі (`кольорові` в `_палітра_образу`), — їх суд іде двома
# варіантами, коли «можливо» нейтраль є (рядок 3360); K-PAL-07 і решта судять вікном самі.
_ПРАВИЛА_КОЛЬОРОВИХ = ("K-PAL-15", "K-PAL-05", "K-PAL-06", "K-PAL-12")


def _палітра_образу(речі, спец_слоти, за_ід, можливі):
    """(знахідки, невідомі, «можливі» елементи) `палітра_образу` на одному варіанті: `можливі` —
    чи рахувати річ-вікно, що «можливо» нейтраль, кольоровою. `невідомі` — {правило: пари} для
    записів «без входу»; «можливі» елементи — речі-вікна по обидва боки межі нейтралі."""
    П = (спец_слоти or {}).get("_палітра")
    if not isinstance(П, dict) or not П.get("вікна"):
        return [], {}, []
    import реєстр_правил as _РЕЄСТР, palettes as _ПЛ, колір_образу as _КО, колір_річ as _КРІЧ
    import колір_нейтралі as _КН
    рівень = (спец_слоти or {}).get("_контраст")
    # НАМІР ТУТ НЕ ЧИТАЄТЬСЯ, І ЦЕ НЕ ПРОПУСК: `palettes.прийоми` уже склав список
    # активних прийомів ІЗ НАМІРОМ (колор-блок і драматизація залежать від нього),
    # тож питати намір удруге означало б завести другого суддю тієї самої умови.
    активні = {x["прийом"] for x in (П.get("прийоми") or []) if x.get("активний")}
    далекі = (П.get("найдальші") or {}).get("вікна")
    гучно = _РЕЄСТР.C["hi_C"]
    зн = []

    def _дод(правило, сила, ярлик, суть, чому, зняло_б, речі_, слот=None, **решта):
        """Додає знахідку ПРИЙОМУ ПАЛІТРИ до `зн` з повним набором полів судді.

        `сила_нп` береться з `_СИЛА_НП[сила]`, а не рахується тут: сила прийому —
        корпусна (тема-2 §K-PAL), і власне число зробило б цей суддя другим
        джерелом ваги поруч із реєстром. `впевненість=1.0` і `бік="код"` — бо
        прийом читається з самої схеми палітри, не з фото."""
        зн.append(dict(правило=правило, сила=сила, сила_нп=_СИЛА_НП[сила], впевненість=1.0,
                       регістр=_РЕЄСТР.регістр(правило, сила), бік="код",
                       сила_нп_джерело="корпусна сила прийому палітри (тема-2 §K-PAL)",
                       слот=слот, речі=[x for x in речі_ if x], ярлик=ярлик,
                       суть=суть, чому=чому, що_зняло_б=зняло_б, **решта))

    точки = _кольори_образу(речі, за_ід)
    # НЕЙТРАЛЬ І МЕТАЛ ВИХОДЯТЬ ІЗ-ПІД ЦИХ ПРАВИЛ, і з тієї самої причини, що в
    # `схема_образу`: нейтраль законна під будь-яку схему (K-COL-06), а фурнітуру
    # судить метал палітри (K-PAL-11), не дуга сім'ї.
    ел = {id(t[0]): _елемент_точки(t, за_ід) for t in точки}
    нв = lambda t: _КО.не_вимір(ел[id(t[0])])
    кол = lambda t: _КРІЧ._не(_КН._нейтраль_межі(dict(ел[id(t[0])], нейтраль=_нейтральний_тон(t[4], t[3], t[2]))))
    кольорові = [t for t in точки if (кол(t) == "так" or (можливі and кол(t) == "невідомо"))
                 and not _ПЛ.метал_речі(_lab_з(t[2], t[3], t[4]), t[1])]
    можливі_ел = [ел[id(t[0])] for t in точки if кол(t) == "невідомо"
                  and not _ПЛ.метал_речі(_lab_з(t[2], t[3], t[4]), t[1])]
    # ── ПРИЙОМИ НАД РІЧЧЮ — «ТАК / НІ / НЕВІДОМО» ВІКНОМ СЛОВА (КОЛІР-ВІКНО-СУД, рядок 3080) ──
    # ЩО БУЛО. K-PAL-09/14/10 (колір у вікнах палітри чи найдальших), K-PAL-02 і K-PAL-13 (тон у
    # дузі очей) і K-PAL-07 (сім'я великої речі) питали точку `_кольори_образу`, а для кольору зі
    # слова точка — центр вікна: «синій» ставав «кольором поза палітрою» чи «не від очей» лише
    # тому, що центр вікна туди впав. ЩО СТАЛО. Річ-вікно судиться всім вікном
    # (`колір_річ.нейтраль_меж`, `у_вікнах_меж`, `у_дугах_меж`): вирок — коли його дає кожна
    # точка вікна, «невідомо» — запис «без входу» з полем `колір_не_вимір` (п.4, п.18). Вимір —
    # точкою, як доти. `кольорові` (K-PAL-15/05/06/12 — різниця між речами) — двома варіантами
    # «можливо» нейтралі (рядок 3360, `палітра_образу`).
    _дуги_вікон = lambda вв: [a for arcs in (вв.get("сім_ї") or {}).values() for a in (arcs or ())]
    _у_в = lambda t, вв: (_КРІЧ.у_вікнах_меж(ел[id(t[0])], вв["L"], вв["C"], _дуги_вікон(вв), _ЗАПАС_ДУГИ)
                          if вв else "ні")
    кандидати = [t for t in точки if кол(t) != "ні" and not _ПЛ.метал_речі(_lab_з(t[2], t[3], t[4]), t[1])]
    поза_в = {id(t[0]): _КРІЧ._і(кол(t), _КРІЧ._не(_у_в(t, П["вікна"]))) for t in кандидати}
    поза_палітрою = [t for t in кандидати if поза_в[id(t[0])] == "так"]
    може_поза = [t for t in кандидати if поза_в[id(t[0])] == "невідомо"]
    # ── РІЗНИЦЯ МІЖ КОЛЬОРАМИ РЕЧЕЙ — ЛИШЕ НА ВИМІРІ (23.09.2026, рядок 141) ──
    # K-PAL-08, K-PAL-15, K-PAL-05 і K-PAL-12 міряють РІЗНИЦЮ між кольорами речей:
    # розмах і крок світлоти, розведення тону. Колір зі слова — центр вікна, і
    # різниця між ним і сусідом — наслідок побудови. Де хоч один колір не вимір
    # (`колір_образу.не_вимір`), різниця — інтервал на межах вікон
    # (`межі_кольору`, `розкид_осі`, `розкид_тону`): висновок, що тримається на
    # всьому інтервалі, стоїть із поміткою «на рівні вікон, не виміру»; решта —
    # запис «без входу» з названим полем. Для вимірів інтервал — точка, тож образ
    # самих вимірів судиться рівно як доти (ті самі пороги, той самий текст).
    # ── ГУЧНІСТЬ РЕЧІ — МЕЖАМИ ВІКНА, А НЕ ХРОМОЮ ЦЕНТРУ (КОЛІР-Р4-2б, рядок 3030) ──
    # ЩО БУЛО. K-PAL-15 («два гучні»), K-PAL-05 (лічба гучних), K-PAL-06 і K-PAL-12 рахували річ
    # гучною за `t[3] >= hi_C` — хромою точки, а для кольору зі слова точка — центр вікна:
    # «зелений» (центр C* 52, виміри того самого слова — медіана 22–26) витрачав бюджет гучних,
    # хоч K-COL-02 (`колір_хрома`) і K-ACC-01 його вже не рахували. ЩО СТАЛО. Гучність — одна,
    # `колір_річ.гучність_меж`: «так» — уся хрома вікна над `hi_C` (вимір — як доти, точкою),
    # «ні» — уся під ним, «можливо» — висновок, що на ній стоїть, іде записом «без входу».
    гуч = lambda t: гучність_меж(ел[id(t[0])])
    невідомі = {}

    def _розмах(ts):
        """(мін, макс) розмаху світлоти набору: для вимірів — одне число двічі."""
        м = [_КО.межі_кольору(ел[id(t[0])]) for t in ts]
        return (max(0.0, max(x[0] for x in м) - min(x[1] for x in м)),
                max(x[1] for x in м) - min(x[0] for x in м))

    def _понад(інт, поріг):
        """«так» / «ні» / «невідомо»: чи величина з інтервалом `інт` БІЛЬША за поріг."""
        return "так" if інт[0] > поріг else ("ні" if інт[1] <= поріг else "невідомо")

    def _нижче(інт, поріг):
        """«так» / «ні» / «невідомо»: чи величина з інтервалом `інт` МЕНША за поріг."""
        return "так" if інт[1] < поріг else ("ні" if інт[0] >= поріг else "невідомо")

    def _слова_розмаху(інт, бік):
        """«53» для виміру; «щонайменше 50» / «щонайбільше 28» для інтервалу на вікнах."""
        if abs(інт[1] - інт[0]) < 1e-9:
            return "%.0f" % інт[0]
        return ("щонайменше %.0f" % інт[0]) if бік == "понад" else ("щонайбільше %.0f" % інт[1])

    # ── K-PAL-14 / K-PAL-09: ЩО НОСИТИ БІЛЯ ОБЛИЧЧЯ ─────────────────────────
    # «Кольори палітри біля обличчя; кольори поза палітрою — у слоти далі від
    # обличчя» (K-PAL-09, default) і «найдальші — область із усіма осями,
    # оберненими проти домінанти» (K-PAL-14, hint).
    # ВОНИ НЕ ВИКЛЮЧАЮТЬ ОДНЕ ОДНОГО, І ЦЕ РІШЕННЯ, ЗМІНЕНЕ ПІД ЧАС ПРАВКИ.
    # Перша редакція давала на річ рівно одне з двох («14 названо — 09 мовчить»),
    # і це виявилось хибним із двох боків. По суті: корпус пов'язує їх ПРЯМО —
    # «labelled furthest, not forbidden; K-PAL-08 and K-PAL-09 say how to carry
    # them anyway», тобто 14 називає колір, а 09 каже, куди його подіти; разом
    # вони одна порада, поодинці — половина. По факту: взаємне виключення лишало
    # K-PAL-09 самий залишок (тони, що не лежать ні у вікнах палітри, ні в
    # найдальших) — на стенді це порожня множина, і правило `default`-сили
    # мовчало б на кожному живому вході. Одне правило — один рядок у вердикті
    # (`знахідки_вердикту` зливає за `правило`), тож два рядки тут — це два різні
    # твердження, а не дубль.
    for t in поза_палітрою + може_поза:
        r, с, L, C, h, near = t
        if near < _КО.NEAR_МІН:
            continue                        # далеко від обличчя — K-PAL-09 це й дозволяє
        if поза_в[id(r)] == "невідомо":
            невідомі.setdefault("K-PAL-09", []).append((ел[id(r)],))
            continue
        якнайдалі = [x for x in (_КО.SLOT_NEAR_FALLBACK or {}) if _КО.SLOT_NEAR_FALLBACK[x] <= 0.2]
        _в14 = _у_в(t, далекі)
        if _в14 == "невідомо":
            невідомі.setdefault("K-PAL-14", []).append((ел[id(r)],))
        if _в14 == "так":
            _дод("K-PAL-14", "hint", "найдальший колір біля обличчя",
                 "«%s» стоїть біля обличчя, а її колір лежить у найдальшій від ваших осей "
                 "області (%s): жодної спільної характеристики з вами"
                 % (с or "річ", (П.get("найдальші") or {}).get("словами") or "всі осі обернені"),
                 "практики дають «найдальші» як відповідь на «чого уникати»; це не заборона — "
                 "K-PAL-08 і K-PAL-09 кажуть, як їх усе ж нести",
                 "той самий колір у слоті далі від обличчя (%s) або колір із палітри у «%s»"
                 % (", ".join(sorted(якнайдалі)[:3]), с or "цьому слоті"),
                 [r.get("id")], слот=с,
                 заяви=[_ВМ.заява("farthest_colour_near_face", slot=_сл_код(с))],
                 ремонт_заяви=[_ВМ.заява("move_colour_away_from_face", slot=_сл_код(с),
                                         far_slots=[_сл_код(x) for x in sorted(якнайдалі)[:3]])])
        _дод("K-PAL-09", "default", "колір поза палітрою біля обличчя",
             "«%s» стоїть біля обличчя (вага %.2f), а її колір поза вікнами вашої палітри"
             % (с or "річ", near),
             "індукція локальна (Chevreul: найсильніша на лінії контакту), тому практики "
             "тримають кольори поза палітрою далі від обличчя",
             "перенести цей колір у слот далі від обличчя (%s) або взяти колір палітри"
             % ", ".join(sorted(якнайдалі)[:3]),
             [r.get("id")], слот=с,
             заяви=[_ВМ.заява("off_palette_colour_near_face", slot=_сл_код(с), nearness=round(near, 2))],
             ремонт_заяви=[_ВМ.заява("move_colour_away_from_face", slot=_сл_код(с),
                                     far_slots=[_сл_код(x) for x in sorted(якнайдалі)[:3]])])

    # ── K-PAL-08: КОНТРАСТ ЯК НОСІЙ ─────────────────────────────────────────
    # «Колір поза палітрою можна нести, якщо контраст образу збігається з
    # контрастом людини» (Lamport, hint). Отже правило говорить рівно тоді, коли
    # такий колір В ОБРАЗІ Є: інакше воно не має про що судити. Смуги збігу —
    # ті самі числа K-PAL-15, якими код уже породжує трійки, а не нові.
    if (поза_палітрою or може_поза) and len(точки) >= 2:
        розмах = _розмах(точки)
        бік = "понад" if рівень == "низький" else "нижче"
        стан = (_понад(розмах, _ПЛ.РОЗМАХ_НИЗЬКОГО) if рівень == "низький" else
                _нижче(розмах, _ПЛ.РОЗМАХ_ВИСОКОГО) if рівень == "високий" else "ні")
        if стан == "так" and not поза_палітрою:
            стан = "невідомо"               # контраст не той, а чи є колір поза палітрою — вирішує вікно
        if стан == "невідомо":
            невідомі["K-PAL-08"] = [(ел[id(t[0])],) for t in точки if нв(t)]
        if стан == "так":
            _дод("K-PAL-08", "hint", "колір поза палітрою без носія",
                 "в образі є колір поза палітрою, а контраст образу (розмах світлоти %s) "
                 "не збігається з вашим (%s) — нести його нема на чому%s"
                 % (_слова_розмаху(розмах, бік), рівень,
                    "; на рівні вікон, не виміру" if any(нв(t) for t in точки) else ""),
                 "Lamport: «easier to wear less flattering colours if you're wearing the right "
                 "contrast levels» — носієм чужого кольору є саме збіг контрастів",
                 "звести контраст образу до вашого або лишити колір поза палітрою в слоті "
                 "далі від обличчя",
                 [t[0].get("id") for t in поза_палітрою],
                 заяви=[_ВМ.заява("off_palette_colour_contrast_mismatch",
                                  lightness_range=[round(розмах[0]), round(розмах[1])],
                                  her_level=_ВМ.код_або_невідомо("contrast_level", рівень),
                                  **({"on_windows": True} if any(нв(t) for t in точки) else {}))],
                 ремонт_заяви=[_ВМ.заява("match_contrast_or_move_colour")])

    # ── K-PAL-15: ПОЄДНАННЯ — ТА САМА ЛОГІКА, ЩО В ТРІЙКАХ ──────────────────
    # Код видає жінці трійки (`palettes.поєднання`); той самий набір перевірок
    # (`palettes.набір_законний`) тепер судить те, що склала модель. Один емітент
    # логіки, не два: інакше система пропонувала б те, що сама відхиляє.
    # ГОЛОСИ, А НЕ РЕЧІ (ФОКУС-2, 03.10.2026, рядок 1461; аудит/ПРОДУКТ.md п.4, п.17). Трійка — три
    # РІЗНІ кольори; в образі зелена сумка й зелені сережки — ОДИН колір, повторений у двох
    # рознесених точках, тобто відлуння, якого вимагає K-COMP-05. Доти логіка трійки лічила
    # речі: сумка й сережки того самого тону ставали «двома гучними кольорами», а крок
    # світлоти між ними — «кольори злипаються», і ремонт знімав колір (живий ПІСЛЯ ФОКУС-1:
    # `more_than_one_loud_colour` — 11 з 27 кольорових образів, ж1 o6, ж4 o2). Тепер речі
    # спершу зводяться в голоси тоном (дуга `_СУСІДНІ_ТОНИ`, та сама, що в K-COL-05 і в
    # групах фокусів K-CRA-02); на слові голоси зводить лише «так», розводить лише «ні»,
    # а висновок, що стоїть на парі «невідомо», іде записом «без входу» (рядок 141). Логіка
    # трійки судить представників голосів (найгучнішу річ кожного), розмах — увесь образ.
    поруч_т = lambda a, b: _КО.відношення(ел[id(a[0])], ел[id(b[0])], "same_hue")
    голоси = []
    for t in кольорові:
        g = next((g for g in голоси if поруч_т(g[0], t) == "так"), None)
        if g is None:
            голоси.append([t])
        else:
            g.append(t)
    голос = {id(t): i for i, g in enumerate(голоси) for t in g}
    предст = [max(g, key=lambda t: t[3]) for g in голоси]
    _заяви_з = []
    законно, чому_ні = True, None
    if len(кольорові) >= 2 and not any(нв(t) for t in кольорові):
        # Крок і гучність — по голосах, розмах — по ВСІХ кольорових речах (рядок 1920): доти
        # розмах брався з представників, і з одним голосом (сумка й сережки того самого
        # тону L20 і L75) не перевірявся зовсім, хоч гілка вікон міряла весь образ.
        законно, чому_ні, _заяви_з = _ПЛ.набір_законний_заява(
            [(t[2], t[3]) for t in предст], рівень, світлоти=[t[2] for t in кольорові])
    elif len(кольорові) >= 2:
        # Ті самі три перевірки, що в `palettes.набір_законний`, і так само УСІ, не перша
        # (рядок 1920), але крок і розмах — на інтервалах вікон. Гучність — властивість
        # КОЖНОЇ речі (хрома проти стелі), а не різниця між ними, і лишається як є.
        # Пари — лише між РІЗНИМИ голосами; пара, чий тон «невідомо», може бути тим
        # самим кольором, тож «крок замалий» чи «два гучні» на ній — теж «невідомо».
        _крок = _РЕЄСТР.C["step_min"]
        _пари = [(a, b) for i, a in enumerate(кольорові) for b in кольорові[i + 1:]
                 if голос[id(a)] != голос[id(b)]]
        _тон = [поруч_т(a, b) for a, b in _пари]
        _кроки = []
        for (a, b), т in zip(_пари, _тон):
            # «крок замалий» — заперечення класу `value_step` API відношень (КОЛІР-Р4, рядок 2950)
            к = {"так": "ні", "ні": "так"}.get(_КО.відношення(ел[id(a[0])], ел[id(b[0])], "value_step"), "невідомо")
            _кроки.append("невідомо" if к == "так" and т == "невідомо" else к)
        # «два гучні» — лише коли обидві речі гучні напевно; «можливо» в парі робить його
        # «невідомо», як і тон «невідомо» (рядок 3030); пара з тихою річчю — не про гучних
        _гучні_пари = [(п, т if {гуч(п[0]), гуч(п[1])} == {"так"} or т != "ні" else "невідомо")
                       for п, т in zip(_пари, _тон) if not {гуч(п[0]), гуч(п[1])} & {"ні", None}]
        _р = _розмах(кольорові)
        _межа = _ПЛ.РОЗМАХ_НИЗЬКОГО if рівень == "низький" else _ПЛ.РОЗМАХ_ВИСОКОГО
        _рст = (_понад(_р, _межа) if рівень == "низький" else
                _нижче(_р, _межа) if рівень == "високий" else "ні")
        _чому = []
        if "так" in _кроки:
            _чому.append("кроку світлоти між кольорами менше за %.0f L* (на рівні вікон, не виміру)" % _крок)
            _заяви_з.append(_ВМ.заява("colour_step_below_min", step_min=round(_крок), on_windows=True))
        if any(т == "ні" for _, т in _гучні_пари):
            _чому.append("гучних кольорів більше за один (хрома ≥ %.0f)" % гучно)
            _заяви_з.append(_ВМ.заява("more_than_one_loud_colour", loud_from=round(гучно)))
        if _рст == "так":
            _чому.append("розмах світлоти %s L* при %s контрасті людини (стеля %.0f / підлога %.0f; "
                         "на рівні вікон, не виміру)"
                         % (_слова_розмаху(_р, "понад" if рівень == "низький" else "нижче"), рівень,
                            _ПЛ.РОЗМАХ_НИЗЬКОГО, _ПЛ.РОЗМАХ_ВИСОКОГО))
            _заяви_з.append(_ВМ.заява("lightness_range_off_her_contrast",
                                      lightness_range=[round(_р[0]), round(_р[1])],
                                      her_level=_ВМ.код_або_невідомо("contrast_level", рівень),
                                      limit=round(_межа), on_windows=True))
        if _чому:
            законно, чому_ні = False, "; ".join(_чому)
        elif ("невідомо" in _кроки or any(т == "невідомо" for _, т in _гучні_пари)
              or _рст == "невідомо"):
            невідомі["K-PAL-15"] = ([(ел[id(a[0])], ел[id(b[0])]) for (a, b), к in zip(_пари, _кроки)
                                    if к == "невідомо"]
                                   + [(ел[id(a[0])], ел[id(b[0])]) for (a, b), т in _гучні_пари
                                      if т == "невідомо"]
                                   + ([(ел[id(t[0])],) for t in кольорові if нв(t)]
                                      if _рст == "невідомо" else []))
    if len(кольорові) >= 2:
        if not законно:
            # Ремонт — лише там, де корпус велить міняти (аудит/ПРОДУКТ.md п.4, п.17). Два РІЗНІ гучні
            # кольори K-COL-02 не забороняє («≤1–2 highly saturated elements», тема-4:290), а
            # понад два судить сам K-COL-02 (`loud_elements_over_budget`, `бюджет_і_відлуння`).
            # Тож «гучних більше одного» — інформація без ремонту, але лише коли це ЄДИНА вада:
            # крок і розмах світлоти поруч із нею ремонт просять, як доти (рядок 1920).
            _гучно_лише = all(з.get("code") == "more_than_one_loud_colour" for з in _заяви_з)
            _дод("K-PAL-15", "hint", "кольори образу не в логіці ваших поєднань",
                 "кольори образу разом не тримають тієї логіки, якою складені ваші поєднання: %s" % чому_ні,
                 "стиліст видає не палітру, а готові трійки; вони будуються кроком світлоти "
                 "(K-COL-01), бюджетом хроми (K-COL-02) і вашим рівнем контрасту",
                 ("два гучні кольори — у межах бюджету K-COL-02 (1–2): ремонту не просить"
                  if _гучно_лише else "розвести світлоти кольорів або лишити гучним лише один"),
                 [t[0].get("id") for t in кольорові],
                 заяви=[_ВМ.заява("colours_off_her_combination_logic")] + _заяви_з,
                 **({} if _гучно_лише else {"ремонт_заяви": [_ВМ.заява("separate_lightness_or_one_loud")]}))

    # ── K-PAL-02: АКЦЕНТ БЕРЕТЬСЯ ВІД ОЧЕЙ ПЕРШИМ ────────────────────────────
    # «Повторити колір очей як акцент … завжди доступний, ПЕРШИЙ за порядком»
    # (R-COL-17, Perrett 2023: одяг обирають до райдужки, не до шкіри; 200
    # учасників, T2). У пулі це вже діє рангом рядка, але ранг розв'язує лише
    # НІЧИЮ — а тут питання інше й перевірне: слот, якому СХЕМА дала роль акценту,
    # несе колір із сім'ї очей чи чужий. Мовчимо, коли акцент нейтральний: «нема
    # акценту» — це K-PAL-18, інше правило й інший ремонт.
    # ІНФОРМАЦІЯ, НЕ РЕМОНТ (ФОКУС-2, 03.10.2026, рядок 1461; аудит/ПРОДУКТ.md п.4, п.17). Корпус
    # (тема-2:1848, K-PAL-02 default): «repeat the eye colour as accent … Always available;
    # first in order» — це ПОРЯДОК прийомів, а не вада чужого акценту: ніде не сказано, що
    # акцент поза сім'єю очей хибний чи що його прибирати. Доти знахідка везла ремонт
    # `accent_in_eye_family`, і ремонт міняв акцент схеми на річ із дуги очей — на
    # ж4 (очі 25–85°) зелену сумку на коричневу, тобто колір схеми на нейтраль: живий
    # ПІСЛЯ ФОКУС-1, 16 з 43 кольорових образів, де вона стояла, втратили колір. Тепер
    # знахідка лишає заяву (стилістка знає, що є перший за порядком прийом), а ремонту
    # не везе — вибір кольору акценту за схемою, її бажанням чи свідомим ходом стилістки.
    очі_дуги_02 = (П["вікна"].get("сім_ї") or {}).get("очі") or []
    if очі_дуги_02:
        for t in кандидати:
            r, с, L, C, h, near = t
            сп = (спец_слоти or {}).get(с)
            if not isinstance(сп, dict) or сп.get("роль") != "акцент":
                continue
            _н02 = _КРІЧ._і(кол(t), _КРІЧ._не(_КРІЧ.у_дугах_меж(ел[id(r)], очі_дуги_02, _ЗАПАС_ДУГИ)))
            if _н02 == "невідомо":
                невідомі.setdefault("K-PAL-02", []).append((ел[id(r)],))
            if _н02 != "так":
                continue
            _дод("K-PAL-02", "hint", "акцент не від очей",
                 "слот «%s» несе акцент, а його тон (%.0f°) не з сім'ї ваших очей (%s)"
                 % (с, h, "; ".join("%.0f–%.0f°" % (a[0], a[1]) for a in очі_дуги_02)),
                 "Perrett 2023: одяг обирають до райдужки, не до шкіри; практики ставлять "
                 "перегук очей першим прийомом — це колір, який у людини вже є",
                 "акцент у сім'ї очей (%s) у слоті «%s»"
                 % ("; ".join("%.0f–%.0f°" % (a[0], a[1]) for a in очі_дуги_02), с),
                 [r.get("id")], слот=с,
                 заяви=[_ВМ.заява("accent_not_from_eyes", slot=_сл_код(с), hue=round(h),
                                  eye_arcs=[[round(a[0]), round(a[1])] for a in очі_дуги_02])])

    # ── K-PAL-05 / 06: ЯКИЙ ПРИЙОМ ОБРАЗ РЕАЛІЗУЄ — І ЧИ ВІН ЇЇ ──────────────
    # Прийоми — оператори з УМОВОЮ («середній/високий контраст», «на м'якій людині
    # обидва приглушені», «для низького контрасту акцент приглушений»). Умова
    # рахувалась у `palettes.прийоми` і вирішувала лише, чи називати прийом
    # доступним; що образ РЕАЛІЗУЄ саме цей прийом і порушує саме його умову, не
    # питав ніхто. Тут образ спершу ВПІЗНАЄТЬСЯ, а тоді перевіряється умова
    # впізнаного — не всіх підряд: інакше на кожен образ висипалось би по чотири
    # hint-и про прийоми, яких у ньому нема.
    if len(кольорові) >= 2:
        м_яка = (П.get("осі") or {}).get("позиція", {}).get("chroma", 0.0) < 0
        # Розведення тону між речами — на тому самому колі художника, що й палітра; для
        # вікна слова — інтервал на дугах вікон (рядок 141): комплемент стверджується, лише
        # коли ВСЯ пара дуг розведена на ≥150°; «може бути» при зайвих гучних — «без входу».
        # Гучність — кожної речі. Вердикт і Δ кола — клас «complementary» API відношень з мірою
        # (КОЛІР-Р4, рядок 2950) і на вимірі теж: доти гілка вимірів міряла тон точкою сама.
        _т = [(ел[id(a[0])], ел[id(b[0])]) + _КО.відношення(ел[id(a[0])], ел[id(b[0])], "complementary", міра=True)
              for i, a in enumerate(кольорові) for b in кольорові[i + 1:]]
        # гучні — `гучність_меж` (рядок 3030): «так» лічиться, «можливо» — лише в межі «без входу»
        гучних = sum(1 for t in кольорові if гуч(t) == "так")
        _може = [t for t in кольорові if гуч(t) == "можливо"]
        треба = 0 if м_яка else 1
        if (гучних + len(_може) > треба and not any(р[2] == "так" for р in _т)
                and any(р[2] == "невідомо" for р in _т)):
            невідомі["K-PAL-05"] = [(р[0], р[1]) for р in _т if р[2] == "невідомо"]
        дельти = [р[3][0] for р in _т if р[2] == "так"]
        if any(d >= 150 for d in дельти) and гучних <= треба < гучних + len(_може):
            # комплемент є, а чи гучних понад дозволені — вирішує річ-вікно «можливо»
            невідомі["K-PAL-05"] = невідомі.get("K-PAL-05", []) + [(ел[id(t[0])],) for t in _може]
        if any(d >= 150 for d in дельти):
            # K-PAL-05 приглушена комплементарна: «один із двох приглушений або малий;
            # на м'якій людині — обидва приглушені»
            if гучних > треба:
                _дод("K-PAL-05", "default", "комплементарна пара не приглушена",
                     "образ веде комплементарна пара (розведення тону %s%.0f°), а гучних кольорів %d "
                     "при дозволених %d%s%s" % ("щонайменше " if any(нв(t) for t in кольорові) else "",
                                                max(дельти), гучних, треба,
                                                " — ваша палітра м'яка, тут приглушені обидва" if м_яка else "",
                                                "; на рівні вікон, не виміру"
                                                if any(нв(t) for t in кольорові) else ""),
                     "прийом дозволяє комплемент лише коли один із двох приглушений або малий; "
                     "на м'якій людині — обидва (K-COL-03, бюджет хроми)",
                     "приглушити один із двох кольорів або лишити його малою площею",
                     [t[0].get("id") for t in кольорові if гуч(t) == "так"],
                     заяви=[_ВМ.заява("complementary_pair_not_muted", hue_gap=round(max(дельти)), loud=гучних,
                                      allowed=треба, **({"soft_palette": True} if м_яка else {}),
                                      **({"on_windows": True} if any(нв(t) for t in кольорові) else {}))],
                     ремонт_заяви=[_ВМ.заява("mute_one_colour_or_small_area")])
        # K-PAL-04 (аналогова) ВЕРДИКТУ ТУТ НЕ МАЄ, І ЦЕ РІШЕННЯ, А НЕ ПРОПУСК.
        # Перша редакція давала знахідку «аналогова пара, а прийом не в наборі для
        # вашого контрасту» — і гілка виявилась недосяжною за побудовою: корпус не
        # вимикає аналогову на жодному контрасті («низький/середній; на високому
        # крок ΔL обовʼязковий»), тож умова «прийом недоступний» хибна завжди.
        # А те, що правило справді стверджує над образом — крок світлоти між
        # сім'ями — уже міряє `набір_законний` (K-PAL-15) тим самим `step_min`
        # K-COL-01; другий рядок про те саме число був би не другим правилом, а
        # тим самим удвічі. K-PAL-04 діє там, де має: він ПОРОДЖУЄ аналогові трійки
        # (`palettes.поєднання` з ід="K-PAL-04") і стоїть у пакеті й описі серед
        # прийомів, доступних цій людині, зі своєю умовою.

    # ── K-PAL-06: НЕЙТРАЛІ ПЛЮС ОДИН АКЦЕНТ ──────────────────────────────────
    # «Нейтралі людини + один акцент, перший — сім'я очей; дефолт для високого
    # контрасту; ДЛЯ НИЗЬКОГО АКЦЕНТ ПРИГЛУШЕНИЙ» (K-COL-03; palettehunt; Lamport).
    # ЧОМУ ПОЗА ЛАНЦЮЖКОМ ВПІЗНАВАННЯ ВИЩЕ, І ЦЕ ВИПРАВЛЕННЯ, А НЕ СМАК: той
    # ланцюжок стоїть під `len(кольорові) >= 2`, бо впізнає ВІДНОШЕННЯ між двома
    # кольорами (комплемент, сусідні сім'ї). А цей прийом упізнається якраз
    # ОДНИМ кольоровим на тлі нейтралей — тобто під тією умовою він недосяжний за
    # побудовою. Спіймано пробою: образ «гучна сорочка + три нейтралі» на
    # низькоконтрастній жінці проходив мовчки.
    # Гучність акценту — `гучність_меж` (рядок 3030): вікно слова — «так» лише всією хромою над
    # стелею (у текст — нижня межа), «можливо» — «без входу»; вимір — як доти.
    _г06 = гуч(кольорові[0]) if len(кольорові) == 1 and len(точки) > 1 and рівень == "низький" else None
    if _г06 == "можливо":
        невідомі["K-PAL-06"] = [(ел[id(кольорові[0][0])],)]
    if _г06 == "так":
        акц = кольорові[0]
        _C06 = _КО.межі_кольору(ел[id(акц[0])])[2]
        _дод("K-PAL-06", "default", "акцент не приглушений на низькому контрасті",
             "образ — ваші нейтралі плюс один акцент, і акцент гучний (хрома %s%.0f ≥ %.0f) "
             "при низькому контрасті" % ("щонайменше " if нв(акц) else "", _C06, гучно),
             "прийом дає для низького контрасту приглушений акцент: гучний на низькому "
             "контрасті читається не як акцент, а як чужа пляма",
             "приглушити акцент або лишити його малою площею",
             [акц[0].get("id")], слот=акц[1],
             заяви=[_ВМ.заява("loud_accent_on_low_contrast", chroma=round(_C06), loud_from=round(гучно),
                              **({"on_windows": True} if нв(акц) else {}))],
             ремонт_заяви=[_ВМ.заява("mute_one_colour_or_small_area")])

    # ── K-PAL-07: КОЛОР-БЛОК ВИМКНЕНО НА НИЗЬКОМУ КОНТРАСТІ ─────────────────
    # `palettes.прийоми` вже вирішує, чи прийом доступний ЦІЙ людині («statement
