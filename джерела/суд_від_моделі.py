def сім_я_слота(слот, _назва=None, тип=None):
    """Сім'я слота з кодів речі; _назва лишена для сумісності старих викликів."""
    слот = str(слот or "")
    if слот in АЛІАС_СІМ_Ї:
        return АЛІАС_СІМ_Ї[слот]
    if слот == "прикраси":
        підслот = _ВМ.СЛОТ_ТИПУ.get(_ВМ.код("item_type", тип))
        return _ВМ.ключ("slot", підслот) if підслот else слот
    return слот


def множина(n, одна, дві, багато):
    """«1 річ · 3 речі · 7 речей». Формулювання набору читає МОДЕЛЬ, і «0 речі» в
    ньому коштувало б рівно того, чим платять за всяку неточність у промпті."""
    n = abs(int(n))
    if n % 100 // 10 == 1:
        return багато
    return {1: одна, 2: дві, 3: дві, 4: дві}.get(n % 10, багато)


