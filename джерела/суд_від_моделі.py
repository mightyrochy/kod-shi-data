# застосовується тут ще раз, над тим, що фактично прийшло в готовий образ.
_АЛІАС_СІМ_Ї = {"клатч": "сумка"}      # рука 3/4 без проходу через feed.слот()


def _сім_я_слота(слот, назва=None):
    """Сім'я слота для лічби «одна річ на сім'ю», а не буквальний слот пулу.

    «сумка»/«клатч» → одна сім'я; «прикраси», коли назва називає сережки,
    кольє, намисто, брошку, браслет чи каблучку, → та сім'я; решта — сама собою."""
    слот = str(слот or "")
    if слот in _АЛІАС_СІМ_Ї:
        return _АЛІАС_СІМ_Ї[слот]
    if слот == "прикраси":
        import feed as _Ф
        т = str(назва or "").lower()
        для = next((під for під, кл in _Ф.ПІД_СЛОТИ_ПРИКРАС if any(k in т for k in кл)), None)
        if для:
            return для
    return слот


def _множина(n, одна, дві, багато):
    """«1 річ · 3 речі · 7 речей». Формулювання набору читає МОДЕЛЬ, і «0 речі» в
    ньому коштувало б рівно того, чим платять за всяку неточність у промпті."""
    n = abs(int(n))
    if n % 100 // 10 == 1:
        return багато
    return {1: одна, 2: дві, 3: дві, 4: дві}.get(n % 10, багато)


