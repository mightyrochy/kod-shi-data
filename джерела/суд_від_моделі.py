# ── КАЗУАЛЬНІШЕ ЗА НАГОДУ: ВІДСІВ НА РІВНІ СУДУ (ВІДСІВ-1) ──────────
# РІШЕННЯ ВЛАСНИКА 02.10: «Відсів має бути на рівні суду. Якщо модель взяла недоречну річ і не
# написала пояснення, чому саме її, значить, можливо, вона помилилася.» Доти (НГ-2б) пул
# знімав речі нижче смуги ошатності ДО стилістки; тепер вони стоять у пулі з позначкою
# (`композитор_придатні.нижче_смуги` — те саме мірило), а суд дивиться на ВІДПОВІДЬ:
#   · річ нижче смуги в образі, пояснення САМЕ ЦІЄЇ речі в «deliberate» нема → знахідка K-KOH-07,
#     регістр «репліка» (не гейт): вона йде у вердикт ремонту з ремонтом «скажи, чому саме ця
#     річ, або візьми ту, що дістає рівня нагоди»;
#   · пояснення є (адресат оголошення — id цієї речі) або річ прийшла за ЇЇ бажанням
#     (`за_бажанням` у пулі: явний вибір жінки сильніший за гейт коду, п.9) → той самий рядок
#     вагою 0, «лише інформація»: у звіт власника, не у вердикт (`знахідки_вердикту` нулі знімає).
# ЧОМУ K-KOH-07, А НЕ K-REG-06. K-REG-06 (hint) — про РЕЄСТР образу: вихід за типовий інтервал
# реєстру — high-low, «не помилка». Тут інше: окрема річ нижча за саму НАГОДУ, а це рівно
# напрям, який K-KOH-07 зве неповагою («Never more than one step off in the direction that
# reads as disrespect», тема-4:494, FORCE `strong`, T3 [sourced]). СИЛА: розрив понад один
# щабель (стеля речі < lo − допуск) — те, що корпус забороняє словом «never», → `strong`; у межах
# щабля (стеля lo − 1, стеля на краї з фото нижче, бал фото без типу) — `soft`: корпус там
# допускає «half a step under», а мірило — один свідок (`ЗАПАС_ФОТО_БЕЗ_ТИПУ`).
# РЕГІСТР «репліка», а не «гейт» і не «питання»: власник каже «можливо, помилилася» — це
# питання до моделі через ремонт, не вето; «питання» ж у вердикт не йде зовсім.
def нижче_смуги_образу(ід, за_ід, сценарій=None, свідомі=None, кандидати=None, *, прогін_руки=None):
    """Знахідки K-KOH-07 (взуття — K-SHO-03) над речами нижче смуги ошатності нагоди.

    `ід` — id речей образу; `за_ід` — каталог за id (мірило бере запис каталогу, як пул);
    `свідомі` — звіт `_застосувати_свідомі` (адресати оголошень); `кандидати` — пул за слотами
    (річ із `за_бажанням` — її бажання). Без смуги нагоди — порожньо (смуги ніхто не казав)."""
    _смуга = _КП.смуга_нагоди(dict(сценарій or {}))
    _допуск = _ФОРМ.допуск_нагоди(_смуга)
    if _допуск is None:
        return []
    _ціль = _ПОЛ.злам("K-KOH-02", "смуга", _смуга, прогін_руки=прогін_руки)
    lo, hi = float(_ціль[0]), float(_ціль[1])
    # хід над іншою знахідкою (прийнятий регістровий гейт над усім образом) — не
    # пояснення речі нижче смуги; пояснює хід без коду чи хід над самою K-KOH-07
    пояснені = {(str(р.get("правило") or "K-KOH-07"), str(x)) for р in (свідомі or []) if isinstance(р, dict)
                and str(р.get("правило") or "K-KOH-07") in ("K-KOH-07", "K-SHO-03")
                for x in ([р.get("ід")] + list(р.get("ід_речей") or []) + list(р.get("адресати") or [])) if x}
    її_бажання = {str(r.get("id")) for пул in (кандидати or {}).values() for r in (пул or [])
                  if isinstance(r, dict) and r.get("за_бажанням")}
    вих = []
    for і in dict.fromkeys(ід or []):
        r = за_ід.get(і)
        if not r:
            continue
        код = _КП.нижче_смуги(r, lo, (сценарій or {}).get("гілка_ошатності"))
        if not код:
            continue
        l, h = _ФОРМ.інтервал_формальності(r)
        стеля = h
        сила = "strong" if стеля < lo - _допуск else "soft"
        правило = "K-SHO-03" if r.get("слот") == "взуття" else "K-KOH-07"
        річ_ф = [l, h]
        за = "deliberate" if (правило, str(і)) in пояснені or ("K-KOH-07", str(і)) in пояснені else ("her_wish" if str(і) in її_бажання else None)
        if за:
            з = _РЕЄСТР.зн(
                правило, сила,
                "річ нижче смуги нагоди %g–%g (%s), і образ каже чому (%s): вибір, не промах"
                % (lo, hi, код, "оголошено в «deliberate»" if за == "deliberate" else "її бажання"),
                [і], "лише інформація: пояснений вибір суд не рахує зауваженням (рішення власника 02.10)",
                заяви=[_ВМ.заява("item_below_occasion_band_explained", reason=код, band=[lo, hi], by=за)])
            # пояснений вибір — лише інформація (рішення власника 02.10): уся готова вага знята
            # єдиним шляхом ваги; `пояснено` — до перезваження, щоб нуль не пішов під підлогу
            з["пояснено"] = за
            з = _РЕЄСТР.перезважити(з, None, частка=_РЕЄСТР.C["пояснений_вибір_вага"])
        else:
            з = _РЕЄСТР.зн(
                правило, сила,
                "річ нижче смуги нагоди %g–%g (%s), а в «deliberate» нема, чому саме вона: можливо, промах"
                % (lo, hi, код),
                [і], "K-KOH-07: ніколи не більш як на щабель у бік, що читається неповагою; мірило — "
                     "`композитор_придатні.нижче_смуги` (інтервал типу, бал фото)",
                ремонт=_пояснення_без_заміни(правило),
                заяви=[_ВМ.заява("item_below_occasion_band_unexplained", reason=код, band=[lo, hi], item=річ_ф, item_id=і, recipient="stylist")],
                ламається="мірило хибить, де тип має лише точку чи бала фото нема (рядки 150, 512); "
                          "тому репліка, не гейт; сила — категорією корпусу, бо шкала 1–10 порядкова")
        вих.append(з)
    return _ПОЛ.злам("K-KOH-07", "суд", вих, смуга=_смуга, ціль=_ціль, ід=ід, прогін_руки=прогін_руки)


