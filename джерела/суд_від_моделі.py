# РЯДОК БЛОКЕРА СТРУКТУРИ — КОД, А НЕ ФРАЗА (п.12, рядок 4251; так само вже зроблено для пальта,
# `суд_погода.блокер_пальта`, рядок 4109). Доти рядок був реченням зі словами й числами («нема
# взуття — без взуття образ не готовий…», «у сім'ї «верх» 2 речі (…)»): його `суть` їхала у звіт
# власника, а `повнота_образу._код_блокера` ЧИТАЛА ті слова, щоб дізнатись код. Тепер рядок —
# `код[:уточнення]`, і читає його лише розбір нижче:
#   код            — один із ключів `_ЧОМУ_БЛОКЕРА` (ядро; англійською `structural_blocker`);
#   уточнення      — через кому, слоти, яких торкається блокер (`слот_двічі`: адреса речей для ремонту,
#                    ті самі, що стояли в лапках рядка) або різновид (`неповний:третя_річ`);
#   `|слоти`       — решта слотів, названих ЗАЯВОЮ, але не адресою (`комплект|верх,низ`).
# Рядок лишається ключем запису: за ним `вердикт_моделі.блокери_структури` знаходить заяви в
# `заяви_блокерів`, тож два блокери одного коду (дві сім'ї з дублем, «третя річ» і «мало речей»)
# мають різні рядки. Що це за блокер, кажуть заяви поруч; речення жінці складає мовна модель.
КОДИ_БЛОКЕРІВ_СТРУКТУРИ = frozenset(_ЧОМУ_БЛОКЕРА)


def рядок_блокера(код, *адреса, ще=()):
    """Рядок блокера з коду й уточнення (див. вище)."""
    р = код + (":" + ",".join(адреса) if адреса else "")
    return р + ("|" + ",".join(ще) if ще else "")


def розібрати_рядок_блокера(рядок):
    """`(код, адреса)` рядка блокера структури, або `(None, [])` для чужого рядка (гейт, вето).
    Читає лише код і слоти після двокрапки — слів рядок не несе."""
    код, _, решта = str(рядок or "").partition(":")
    if код not in КОДИ_БЛОКЕРІВ_СТРУКТУРИ:
        return None, []
    адреса = решта.split("|", 1)[0]
    return код, [x for x in адреса.split(",") if x]


