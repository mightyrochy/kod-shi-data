    зн = list(зн) + _ПОЛ.відсіяти(нижче_смуги_образу(ід, за_ід, сценарій, свідомі, кандидати, прогін_руки=прогін_руки), [r.get("id") for r in речі], прогін_руки=прогін_руки)
