    # каже, що лишити, а що стишити, з урахуванням її вибору (`суд_ремесло`)
    зн = _СР_ф.оголосити_фокус_свідомим(зн, свідомі, (сценарій or {}).get("intent", ТИПОВИЙ_НАМІР))
