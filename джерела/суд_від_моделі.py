# ── СКЛАД КОМПЛЕКТУ КОДОМ (КОМПЛЕКТ-2, рядок 1490, 08.10.2026) ──────────────────────
# Назва половин часто не каже: «Костюм чорний», «Світло-зелений костюм зі спідницею міді»,
# «МОДЕЛЬ №905 СІРИЙ» — 125 комплектів каталогу без жодного слова верху чи шару в назві. Доти
# такий комплект із окремим верхом діставав блокер «подвоєння», хоч код не знав, чи верхня
# половина — жакет (тоді верх під ним — звичайний костюмний образ), чи сама верх; ремонт
# знімав блузу, і рука 1 (ж6_робота_комплементарна) дала «Світло-зелений костюм» без верху.
# Опис фото збагачення («Костюм з курткою та спідницею») — слова, код їх не читає (п.12);
# коду складу збагачення не має. Код дає РОЗБІР КАТАЛОГУ мовною моделлю (п.16):
# `set_parts[].item_type` закритим переліком (`каталог_розбір`), який доїжджає сюди
# `каталог_коди.поля` за id офера. Тож склад: спершу коди розбору; далі позначка пулу і
# слоти пулу (коди); назва — як доти (КОМПЛЕКТ-1). Не каже ніхто — «невідомо», і суд не
# стверджує подвоєння, а питає вхід полем `set_parts` (`структура_образу_заяви`).
_ЧАСТИНА_ШАР = frozenset({"blazer", "jacket", "vest", "cardigan", "coat", "trench_coat"})
_ЧАСТИНА_ВЕРХ = frozenset(т for т, с in _ВМ.СЛОТ_ТИПУ.items() if с in ("top", "dress")) - _ЧАСТИНА_ШАР
ПОЛЕ_СКЛАДУ = "set_parts"


def склад_комплекту(річ, слоти_пулу=None):
    """Верхня половина комплекту: ("шар" | "верх" | None, звідки). "шар" — піджак, жакет, жилет,
    кардиган: один верх під ним — не дубль; "верх" — половина сама верх (сорочка, топ, сукня);
    None — невідомо (звідки = `ПОЛЕ_СКЛАДУ`, якого бракує). `слоти_пулу` — id → слоти пулу."""
    import каталог_коди as _КК
    # частина — шар за типом (жакет, жилет, кардиган) чи за слотом `outerwear`; верх — за типом чи
    # за слотом `top`/`dress` частини (тип поза `СЛОТ_ТИПУ` — боді, лонгслів, трикотаж — слот несе)
    частини = [(str(ч.get("item_type")), str(ч.get("slot"))) for ч in
               (_КК.поля(річ.get("id")).get("set_parts") or ()) if isinstance(ч, dict)]
    шар = [т in _ЧАСТИНА_ШАР or сл == "outerwear" for т, сл in частини]
    if any(not ш and (т in _ЧАСТИНА_ВЕРХ or сл in ("top", "dress")) for (т, сл), ш in zip(частини, шар)):
        return "верх", ПОЛЕ_СКЛАДУ
    if any(шар):
        return "шар", ПОЛЕ_СКЛАДУ
    if річ.get("шар_у_комплекті"):          # позначка пулу (`пакет_моделі.відсікти_пул`)
        return "шар", "шар_у_комплекті"
    т = " ".join(str(річ.get(к) or "") for к in ("тип", "назва", "назва_показу"))
    if _ВЕРХ_У_КОМПЛЕКТІ.search(т):
        return "верх", "назва"
    if "верхній_шар" in (річ.get("слоти_альт") or ()) \
            or "верхній_шар" in ((слоти_пулу or {}).get(str(річ.get("id"))) or ()):
        return "шар", "слоти"
    if _ШАР2.search(т):
        return "шар", "назва"
    return None, ПОЛЕ_СКЛАДУ


def комплект_з_шаром(річ, слоти_пулу=None):
    """True — комплект, чия верхня половина є шаром (`склад_комплекту` == "шар")."""
    return склад_комплекту(річ, слоти_пулу)[0] == "шар"


# ── СІМ'Я СЛОТУ — ОДНЕ МІСЦЕ, ЗВІДКИ ЧИТАЄ І СТРУКТУРА, І РЕМОНТ (рядок 47,
