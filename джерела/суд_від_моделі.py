def _лишити_стишити(гучні_т, фокус=None, схема_слоти=None, за_ід=None):
    """(keep, quiet, keep_by) K-COL-02 — ЯКИЙ гучний лишити, а які стишити (ФОКУС-3, рядок 1521).

    Ремонт «лишити один гучний, решту стишити» не казав, ЯКИЙ: на ж6 р2 (fokus_2/ПІСЛЯ) модель
    знімала зелену сумку — акцент схеми, що відлунює в туфлях, — бо бюджет переповнювало
    волосся. Тут — те саме рішення, що K-CRA-02 (`суд_ремесло.фокуси_знахідка`): гучні речі
    групами одного тону (±15° кола художника, `суд_ремесло.ДУГА_ВІДЛУННЯ`, клас «same_hue»
    `колір_річ.відношення`; колір зі слова — «невідомо» не розводить); група ОГОЛОШЕНА, коли її річ стоїть в акцентному слоті схеми, що
    несе тон дуги (`схема_слоти`, "scheme"), у фокусній зоні сценарію (решта `фокус`, "zone")
    чи це її явний вибір (`регістр_уваги.її_вибір`, "her_wish" — п.9). `keep` — оголошені речі,
    а коли оголошена одна, ще й один носій її тону (відлуння K-COMP-05: ≥2 точки); `quiet` —
    решта гучних, і зайві носії того самого тону теж: бюджет рахує речі. Коди слотів."""
    import колір_образу as _КО, регістр_уваги as _РУ
    схема_слоти = set(схема_слоти or ())
    зона = set(фокус or ()) - схема_слоти
    групи = []
    for t in гучні_т:
        e = _елемент_точки(t, за_ід)
        for g in групи:
            п = g["ел"][0]
            if _КО.відношення(e, п, "same_hue") != "ні":   # два виміри — «так» чи «ні»
                break
        else:
            g = dict(ел=[], оголошені=[], решта=[])
            групи.append(g)
        g["ел"].append(e)
        повна = (за_ід or {}).get(t[0].get("id")) or t[0]
        хто = {х for х, так in (("scheme", t[1] in схема_слоти), ("zone", t[1] in зона),
                                ("her_wish", _РУ.її_вибір(повна))) if так}
        (g["оголошені"] if хто else g["решта"]).append((t[1], хто))
    keep, quiet, keep_by = set(), set(), set()
    for g in групи:
        луна = g["решта"][:1] if len(g["оголошені"]) == 1 else []
        keep |= {с for с, _ in g["оголошені"] + луна}
        quiet |= {с for с, _ in g["решта"] if (с, set()) not in луна}
        keep_by |= {х for _, хто in g["оголошені"] for х in хто}
    кд = lambda сс: sorted({_сл_код(с) for с in сс if с})
    return кд(keep), кд(quiet - keep), sorted(keep_by)


