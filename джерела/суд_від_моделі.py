# ── СІМ'Я СЛОТУ — ОДНЕ МІСЦЕ, ЗВІДКИ ЧИТАЄ І СТРУКТУРА, І РЕМОНТ (рядок 47,
# 19.09.2026). Власник побачив дві пари сережок в ОДНОМУ образі: «Malachite» і
# «золотистого кольору Придане». Правило «по одній речі на слот» рахує буквальний
# слот, а сережки лежать у двох під-слотах — `feed._слот_у_тексті` ділить
# генеричну категорію «прикраси» на під-слоти (`feed.ПІД_СЛОТИ_ПРИКРАС`) ЗА
# НАЗВОЮ під час збору каталогу, і річ, чия назва не збіглася з жодним ключем
# того словника (діалектне слово продавця, річ руки 3/4 без проходу через
# feed), лишається генеричною «прикраси» — дубль для лічби невидимий.
# Ключі НЕ дублюються другим списком: та сама перевірка `feed.ПІД_СЛОТИ_ПРИКРАС`
# застосовується тут ще раз, над тим, що фактично прийшло в готовий образ.
_АЛІАС_СІМ_Ї = {"клатч": "сумка"}      # рука 3/4 без проходу через feed.слот()


def _сім_я_слота(слот, назва=None):
    """Сім'я слота для лічби «одна річ на сім'ю», а не буквальний слот пулу.

    «сумка»/«клатч» → одна сім'я; «прикраси», коли назва називає сережки,
    кольє, намисто, брошку, браслет чи каблучку, → та сім'я; решта — сама собою."""
    слот = str(слот or "")
    if слот in _АЛІАС_СІМ_Ї:
        return _АЛІАС_СІМ_Ї[слот]
    if слот == "прикраси":
        import feed as _Ф
        т = str(назва or "").lower()
        для = next((під for під, кл in _Ф.ПІД_СЛОТИ_ПРИКРАС if any(k in т for k in кл)), None)
        if для:
            return для
    return слот


def _множина(n, одна, дві, багато):
    """«1 річ · 3 речі · 7 речей». Формулювання набору читає МОДЕЛЬ, і «0 речі» в
    ньому коштувало б рівно того, чим платять за всяку неточність у промпті."""
    n = abs(int(n))
    if n % 100 // 10 == 1:
        return багато
    return {1: одна, 2: дві, 3: дві, 4: дві}.get(n % 10, багато)


# ── ЧИ ВЦІЛІВ АКЦЕНТ, ЯКОГО ЗАЖАДАВ САМ КОД ────────────────────────────────
# ЩО ЦЕ ЛОВИТЬ (правило 3, реальний випадок 04.09.2026). Тестувальниця обрала
# червоний і схему «нейтрали+акцент». Спека поклала акцент на взуття й сумку
# (C 28–70, L 57–72). Обидві руки віддали суцільно чорний образ — C ≈ 2 на всіх
# чотирьох слотах. Суддя видав 8 знахідок і ЖОДНОЇ про колір: код приписав
# слоту роль і не перевірив, чи вона виконана. Петля була розімкнена — приписав
# і забув. Мовчання судді неможливо відрізнити від «акцент на місці».
#
# СИЛА ≤ ВЕРИФІКАЦІЯ (правило 4). Тут не стверджується, що образ гірший, — це
# скаже носій. Стверджується рівно те, що вимірюється: код зажадав хрому в
# слоті, річ у слоті її не має. Тому дві РІЗНІ знахідки, бо це два різні
# дефекти з різними адресатами:
#   · пул мав чим — це вибір проти власної спеки (адресат: промпт і модель);
#   · пул не мав чим — це дефіцит каталогу (адресат: закупівля джерел), і
#     звинувачувати модель тут було б помилкою атрибуції.
def схема_образу(речі, спец_слоти, за_ід=None):
    """[знахідки] K-PAL-03 — річ поза дугою обраної схеми, або кольорова річ на
    нейтральній ролі (16.09.2026). Дуга схеми — межа, яку обрала жінка, а не порада:
    доти червона сумка в «тональній сливовій» не давала жодної знахідки."""
    if not спец_слоти or not isinstance(спец_слоти, dict):
        return []
    # ТРАУРНА НАГОДА, СХЕМУ ВЗЯВ КОД (рядок 154): її дуги тут не межа — межу ставить
    # траурний регістр пулу. Виміряно на похороні (сід 3, 10 образів): без цього рядка
    # K-PAL-03 гейтом блокував 2 образи за темно-синю й бордову речі поза бірюзовою
    # дугою «тональної», якої жінка не обирала. Схему, обрану нею, судить як доти.
    if спец_слоти.get("_траур"):
        return []
    import colorspace as _КС, реєстр_правил as _РЕЄСТР, колір_образу as _КО, колір_річ as _КРІЧ
    # РЕГІСТР СТАВИТЬСЯ ТУТ: `протокол.регістр_знахідки` бере його з рядка, а не з
    # політики, тож знахідка без поля йшла б реплікою попри політику «гейт».
    _рег = _РЕЄСТР.регістр("K-PAL-03", "hard")
    зн = []
    for r in речі:
        с = r.get("слот")
        сп = спец_слоти.get(с)
        if not isinstance(сп, dict):
            continue
        дуга, роль = сп.get("дуга_тону"), сп.get("роль")
        повна = (за_ід or {}).get(r.get("id")) or r
        lab = повна.get("lab")
        if not lab and повна.get("hex"):
            try: lab = _КС.hx(повна["hex"])
            except (TypeError, ValueError, AttributeError): lab = None
        if not lab or len(lab) < 3:
            continue
        try:
            L, C, h = _КС.lch(lab)
        except (TypeError, ValueError, AttributeError):
            continue
        if _нейтральний_тон(h, C, L):
            continue                                   # нейтраль законна під будь-яку схему
        схема = спец_слоти.get("_схема", "?")
        if дуга == "нейтраль" and роль in ("домінанта", "секундант"):
            зн.append(dict(правило="K-PAL-03", сила="hard", сила_нп=0.95, впевненість=1.0, регістр=_рег,
                           сила_нп_джерело="межа схеми: роль слота задана обраною схемою",
                           бік="код", слот=с, речі=[r.get("id")],
                           ярлик="кольорова річ на нейтральній ролі",
                           суть="схема «%s» тримає слот «%s» нейтральним, а річ має хрому %.0f" % (схема, с, C),
                           чому="роль слота задана схемою, яку обрала жінка",
                           що_зняло_б="нейтральна річ у слоті «%s»" % с))
            continue
        if not (isinstance(дуга, (list, tuple)) and len(дуга) == 2 and дуга[0] is not None):
            continue
        # Схема великих поверхонь (рядок 133) кладе в пул великої речі ВСІ свої сім'ї
        # (`дуги_схеми`), тож межа слота — кожна з цих дуг, а не лише дуга його ролі.
        в_дузі = any((lo <= hi and lo - 10 <= h <= hi + 10) or (lo > hi and (h >= lo - 10 or h <= hi + 10))
                     for lo, hi in [(float(дуга[0]), float(дуга[1]))]
                     + [(float(д["дуга"][0]), float(д["дуга"][1])) for д in (сп.get("дуги_схеми") or ())])
        lo, hi = float(дуга[0]), float(дуга[1])
        # КОЛІР-СЛОВО — ДУГОЮ ВІКНА, НЕ ТОНОМ ЦЕНТРУ (рядок 162). Пул тепер пускає
        # річ-слово за перетином дуги її вікна з дугою рядка (`фід_добір.описує_річ`),
        # і суд мусить мірятись тією самою міркою: «зелений» (дуга 100–180°, центр
        # h*140) під дугою очей 160–184° не «поза дугою» — його справжній тон може
        # в неї влучати. Уся дуга вікна поза дугою схеми (із запасом) — порушення, як
        # доти; уся всередині — нема чого казати; частково — «без входу» з полем
        # `колір_не_вимір`, а не вирок (рядок 141).
        _вік = _КО.межі_кольору(повна) if _КО.не_вимір(повна) else None
        if _вік is not None and _вік[4] is not None:
            _дуги = [(float(дуга[0]) - 10, float(дуга[1]) + 10)] + [
                (float(д["дуга"][0]) - 10, float(д["дуга"][1]) + 10) for д in (сп.get("дуги_схеми") or ())]
            _дуги = [(a % 360.0, b % 360.0) for a, b in _дуги]
            _w = (_вік[4][0] % 360.0, _вік[4][1] % 360.0)
            _ширина = (_w[1] - _w[0]) % 360.0 or 360.0
            _тони = [(_w[0] + min(k, _ширина)) % 360.0 for k in range(int(_ширина) + 1)]
            _влучає = [any(_КРІЧ._на_дузі(x, д) for д in _дуги) for x in _тони]
            if all(_влучає):
                continue
            if any(_влучає):
                зн.append(_КО.без_входу_кольору(
                    "K-PAL-03", [(повна,)], "чи тримає річ тон дуги схеми",
                    "K-PAL-03 звіряє тон речі з дугою схеми (%.0f–%.0f°), а вікно слова лежить "
                    "по обидва боки її межі" % (lo, hi)))
                continue
            в_дузі = False
        if not в_дузі:
            зн.append(dict(правило="K-PAL-03", сила="hard", сила_нп=0.95, впевненість=1.0, регістр=_рег,
                           сила_нп_джерело="межа схеми: тон речі проти дуги обраної схеми",
                           бік="код", слот=с, речі=[r.get("id")],
                           ярлик="поза дугою схеми",
                           суть="схема «%s»: слот «%s» (роль %s) тримає тон %.0f–%.0f°, а річ має тон %.0f° при хромі %.0f"
                                % (схема, с, роль, lo, hi, h, C),
                           чому="дуга схеми — межа, а не порада: поза нею образ не тримає обраної схеми",
                           що_зняло_б="річ у дузі схеми або нейтральна в слоті «%s»" % с))
    return зн


# ── ПРАКТИКОВА ПАЛІТРА СУДИТЬ ЗІБРАНИЙ ОБРАЗ (K-PAL-07…10, 12, 14, 15) ────────
# ЩО ТУТ БУЛО ДО 17.09.2026. Увесь шар `palettes.py` рахувався на кожному прогоні
# й лишав слід у `trace`: прийоми (K-PAL-02…13), найдальші кольори (K-PAL-14),
# поєднання всередині палітри (K-PAL-15). Жодне з них не судило ОБРАЗ: у вердикт
# від цього шару доїжджали рівно два правила — K-PAL-03 (дуга схеми) і K-PAL-18
# (акцент). Тобто система знала, які кольори найдальші від жінки, і мовчала, коли
# модель ставила саме їх їй до обличчя.
# ЧОМУ СУД, А НЕ ФІЛЬТР ПУЛУ. Прийоми — оператори над ОБРАЗОМ, а не над річчю:
# «контраст як носій» питає про контраст усього образу, «розміщення» — про те, де
# річ стоїть відносно обличчя, «поєднання» — про пари кольорів. Пул їх виконати
# не може за побудовою: у ньому речі стоять поодинці.
_ЗАПАС_ДУГИ = 10.0          # той самий, що в `_у_дузі_вікон` і `схема_образу`

# ШКАЛА FORCE → ВАГА, ОДНА НА МОДУЛЬ. Той самий словник стояв локальним `_НП`
# усередині `перевірити_від_моделі` (16.09: «знахідка без `сила_нп` гине у
# вердикті»); відколи його потребує ще й `палітра_образу`, дві копії розійшлись
# би мовчки — і половина правил палітри важила б не те, що оголосила.
_СИЛА_НП = {"hard": 0.95, "strong": 0.75, "default": 0.5, "soft": 0.35, "hint": 0.2}


def _у_вікнах(вікна, L, C, h):
    """Чи лежить колір у наборі вікон палітри (світлота × хрома × котрась дуга сім'ї)."""
    if not вікна:
        return False
    Llo, Lhi = вікна["L"]; Clo, Chi = вікна["C"]
    if not (Llo <= L <= Lhi) or not (Clo <= C <= Chi):
        return False
    for arcs in (вікна.get("сім_ї") or {}).values():
        for a in (arcs or ()):
            lo, hi = float(a[0]) - _ЗАПАС_ДУГИ, float(a[1]) + _ЗАПАС_ДУГИ
            if (lo <= h <= hi) if lo <= hi else (h >= lo or h <= hi):
                return True
    return False


def _кольори_образу(речі, за_ід=None):
    """[(річ, слот, L, C, h, near)] для речей із ВИМІРЯНИМ кольором.

    `за_ід` обовʼязковий із тієї самої причини, що в `акцент_образу`: рядок пулу,
    який їде моделі, не несе `lab`, і рахувати колір по ньому означало б судити
    дефолтний сірий (див. `bridge.каталог_останнього_пакета`).
    """
    import colorspace as _КС, колір_образу as _КО
    out = []
    for r in (речі or ()):
        повна = (за_ід or {}).get(r.get("id")) or r
        lab = повна.get("lab")
        if not lab and повна.get("hex"):
            try: lab = _КС.hx(повна["hex"])
            except (TypeError, ValueError, AttributeError): lab = None
        if not lab or len(lab) < 3:
            continue
        try: L, C, h = _КС.lch(lab)
        except (TypeError, ValueError, AttributeError): continue
        слот = r.get("слот")
        out.append((r, слот, L, C, h, _КО.SLOT_NEAR_FALLBACK.get(слот, 0.3)))
    return out


def палітра_образу(речі, спец_слоти, за_ід=None):
    """[знахідки] практикових прийомів над зібраним образом.

    Чекає в `спец_слоти` службові ключі, які кладе шов (`bridge._пакет_каталогу`):
    `_палітра` — вихід `palettes.палітра_практична` (вікна, найдальші, активні
    прийоми), `_контраст` — рівень контрасту особи. Без них правила мовчать, і це
    «без входу», а не «пройдено»: перевірка без палітри була б заглушкою,
    невідрізненною від зеленого вердикту. Саме це й показує третій чекліст
    (`суд_образу.ЧЕКЛІСТ_ПАЛІТРИ`), щоб мовчання було видно.
    
    Прийоми, що міряють РІЗНИЦЮ між кольорами речей (K-PAL-08, K-PAL-15, K-PAL-05,
    K-PAL-12), судять лише вимір (рядок 141): де колір речі — центр вікна слова,
    різниця береться інтервалом на межах вікон, а висновок, що на ньому не
    тримається, іде записом «без входу» з названим полем.
    """
    П = (спец_слоти or {}).get("_палітра")
    if not isinstance(П, dict) or not П.get("вікна"):
        return []
    import реєстр_правил as _РЕЄСТР, palettes as _ПЛ, колір_образу as _КО
    рівень = (спец_слоти or {}).get("_контраст")
    # НАМІР ТУТ НЕ ЧИТАЄТЬСЯ, І ЦЕ НЕ ПРОПУСК: `palettes.прийоми` уже склав список
    # активних прийомів ІЗ НАМІРОМ (колор-блок і драматизація залежать від нього),
    # тож питати намір удруге означало б завести другого суддю тієї самої умови.
    активні = {x["прийом"] for x in (П.get("прийоми") or []) if x.get("активний")}
    далекі = (П.get("найдальші") or {}).get("вікна")
    гучно = _РЕЄСТР.C["hi_C"]
    зн = []

    def _дод(правило, сила, ярлик, суть, чому, зняло_б, речі_, слот=None, **решта):
        """Додає знахідку ПРИЙОМУ ПАЛІТРИ до `зн` з повним набором полів судді.

        `сила_нп` береться з `_СИЛА_НП[сила]`, а не рахується тут: сила прийому —
        корпусна (тема-2 §K-PAL), і власне число зробило б цей суддя другим
        джерелом ваги поруч із реєстром. `впевненість=1.0` і `бік="код"` — бо
        прийом читається з самої схеми палітри, не з фото."""
        зн.append(dict(правило=правило, сила=сила, сила_нп=_СИЛА_НП[сила], впевненість=1.0,
                       регістр=_РЕЄСТР.регістр(правило, сила), бік="код",
                       сила_нп_джерело="корпусна сила прийому палітри (тема-2 §K-PAL)",
                       слот=слот, речі=[x for x in речі_ if x], ярлик=ярлик,
                       суть=суть, чому=чому, що_зняло_б=зняло_б, **решта))

    точки = _кольори_образу(речі, за_ід)
    # НЕЙТРАЛЬ І МЕТАЛ ВИХОДЯТЬ ІЗ-ПІД ЦИХ ПРАВИЛ, і з тієї самої причини, що в
    # `схема_образу`: нейтраль законна під будь-яку схему (K-COL-06), а фурнітуру
    # судить метал палітри (K-PAL-11), не дуга сім'ї.
    кольорові = [(r, с, L, C, h, near) for r, с, L, C, h, near in точки
                 if not _нейтральний_тон(h, C, L)
                 and not _ПЛ.метал_речі(_lab_з(L, C, h), с)]
    поза_палітрою = [t for t in кольорові if not _у_вікнах(П["вікна"], t[2], t[3], t[4])]
    # ── РІЗНИЦЯ МІЖ КОЛЬОРАМИ РЕЧЕЙ — ЛИШЕ НА ВИМІРІ (23.09.2026, рядок 141) ──
    # K-PAL-08, K-PAL-15, K-PAL-05 і K-PAL-12 міряють РІЗНИЦЮ між кольорами речей:
    # розмах і крок світлоти, розведення тону. Колір зі слова — центр вікна, і
    # різниця між ним і сусідом — наслідок побудови. Де хоч один колір не вимір
    # (`колір_образу.не_вимір`), різниця — інтервал на межах вікон
    # (`межі_кольору`, `розкид_осі`, `розкид_тону`): висновок, що тримається на
    # всьому інтервалі, стоїть із поміткою «на рівні вікон, не виміру»; решта —
    # запис «без входу» з названим полем. Для вимірів інтервал — точка, тож образ
    # самих вимірів судиться рівно як доти (ті самі пороги, той самий текст).
    ел = {id(t[0]): _елемент_точки(t, за_ід) for t in точки}
    нв = lambda t: _КО.не_вимір(ел[id(t[0])])
    невідомі = {}

    def _розмах(ts):
        """(мін, макс) розмаху світлоти набору: для вимірів — одне число двічі."""
        м = [_КО.межі_кольору(ел[id(t[0])]) for t in ts]
        return (max(0.0, max(x[0] for x in м) - min(x[1] for x in м)),
                max(x[1] for x in м) - min(x[0] for x in м))

    def _понад(інт, поріг):
        """«так» / «ні» / «невідомо»: чи величина з інтервалом `інт` БІЛЬША за поріг."""
        return "так" if інт[0] > поріг else ("ні" if інт[1] <= поріг else "невідомо")

    def _нижче(інт, поріг):
        """«так» / «ні» / «невідомо»: чи величина з інтервалом `інт` МЕНША за поріг."""
        return "так" if інт[1] < поріг else ("ні" if інт[0] >= поріг else "невідомо")

    def _слова_розмаху(інт, бік):
        """«53» для виміру; «щонайменше 50» / «щонайбільше 28» для інтервалу на вікнах."""
        if abs(інт[1] - інт[0]) < 1e-9:
            return "%.0f" % інт[0]
        return ("щонайменше %.0f" % інт[0]) if бік == "понад" else ("щонайбільше %.0f" % інт[1])

    # ── K-PAL-14 / K-PAL-09: ЩО НОСИТИ БІЛЯ ОБЛИЧЧЯ ─────────────────────────
    # «Кольори палітри біля обличчя; кольори поза палітрою — у слоти далі від
    # обличчя» (K-PAL-09, default) і «найдальші — область із усіма осями,
    # оберненими проти домінанти» (K-PAL-14, hint).
    # ВОНИ НЕ ВИКЛЮЧАЮТЬ ОДНЕ ОДНОГО, І ЦЕ РІШЕННЯ, ЗМІНЕНЕ ПІД ЧАС ПРАВКИ.
    # Перша редакція давала на річ рівно одне з двох («14 названо — 09 мовчить»),
    # і це виявилось хибним із двох боків. По суті: корпус пов'язує їх ПРЯМО —
    # «labelled furthest, not forbidden; K-PAL-08 and K-PAL-09 say how to carry
    # them anyway», тобто 14 називає колір, а 09 каже, куди його подіти; разом
    # вони одна порада, поодинці — половина. По факту: взаємне виключення лишало
    # K-PAL-09 самий залишок (тони, що не лежать ні у вікнах палітри, ні в
    # найдальших) — на стенді це порожня множина, і правило `default`-сили
    # мовчало б на кожному живому вході. Одне правило — один рядок у вердикті
    # (`знахідки_вердикту` зливає за `правило`), тож два рядки тут — це два різні
    # твердження, а не дубль.
    for r, с, L, C, h, near in поза_палітрою:
        if near < _КО.NEAR_МІН:
            continue                        # далеко від обличчя — K-PAL-09 це й дозволяє
        якнайдалі = [x for x in (_КО.SLOT_NEAR_FALLBACK or {}) if _КО.SLOT_NEAR_FALLBACK[x] <= 0.2]
        if далекі and _у_вікнах(далекі, L, C, h):
            _дод("K-PAL-14", "hint", "найдальший колір біля обличчя",
                 "«%s» стоїть біля обличчя, а її колір лежить у найдальшій від ваших осей "
                 "області (%s): жодної спільної характеристики з вами"
                 % (с or "річ", (П.get("найдальші") or {}).get("словами") or "всі осі обернені"),
                 "практики дають «найдальші» як відповідь на «чого уникати»; це не заборона — "
                 "K-PAL-08 і K-PAL-09 кажуть, як їх усе ж нести",
                 "той самий колір у слоті далі від обличчя (%s) або колір із палітри у «%s»"
                 % (", ".join(sorted(якнайдалі)[:3]), с or "цьому слоті"),
                 [r.get("id")], слот=с)
        _дод("K-PAL-09", "default", "колір поза палітрою біля обличчя",
             "«%s» стоїть біля обличчя (вага %.2f), а її колір поза вікнами вашої палітри"
             % (с or "річ", near),
             "індукція локальна (Chevreul: найсильніша на лінії контакту), тому практики "
             "тримають кольори поза палітрою далі від обличчя",
             "перенести цей колір у слот далі від обличчя (%s) або взяти колір палітри"
             % ", ".join(sorted(якнайдалі)[:3]),
             [r.get("id")], слот=с)

    # ── K-PAL-08: КОНТРАСТ ЯК НОСІЙ ─────────────────────────────────────────
    # «Колір поза палітрою можна нести, якщо контраст образу збігається з
    # контрастом людини» (Lamport, hint). Отже правило говорить рівно тоді, коли
    # такий колір В ОБРАЗІ Є: інакше воно не має про що судити. Смуги збігу —
    # ті самі числа K-PAL-15, якими код уже породжує трійки, а не нові.
    if поза_палітрою and len(точки) >= 2:
        розмах = _розмах(точки)
        бік = "понад" if рівень == "низький" else "нижче"
        стан = (_понад(розмах, 45) if рівень == "низький" else
                _нижче(розмах, 30) if рівень == "високий" else "ні")
        if стан == "невідомо":
            невідомі["K-PAL-08"] = [(ел[id(t[0])],) for t in точки if нв(t)]
        if стан == "так":
            _дод("K-PAL-08", "hint", "колір поза палітрою без носія",
                 "в образі є колір поза палітрою, а контраст образу (розмах світлоти %s) "
                 "не збігається з вашим (%s) — нести його нема на чому%s"
                 % (_слова_розмаху(розмах, бік), рівень,
                    "; на рівні вікон, не виміру" if any(нв(t) for t in точки) else ""),
                 "Lamport: «easier to wear less flattering colours if you're wearing the right "
                 "contrast levels» — носієм чужого кольору є саме збіг контрастів",
                 "звести контраст образу до вашого або лишити колір поза палітрою в слоті "
                 "далі від обличчя",
                 [t[0].get("id") for t in поза_палітрою])

    # ── K-PAL-15: ПОЄДНАННЯ — ТА САМА ЛОГІКА, ЩО В ТРІЙКАХ ──────────────────
    # Код видає жінці трійки (`palettes.поєднання`); той самий набір перевірок
    # (`palettes.набір_законний`) тепер судить те, що склала модель. Один емітент
    # логіки, не два: інакше система пропонувала б те, що сама відхиляє.
    if len(кольорові) >= 2 and not any(нв(t) for t in кольорові):
        законно, чому_ні = _ПЛ.набір_законний([(t[2], t[3]) for t in кольорові], рівень)
    elif len(кольорові) >= 2:
        # Ті самі три перевірки, що в `palettes.набір_законний`, і в тому самому
        # порядку, але крок і розмах — на інтервалах вікон. Гучність — властивість
        # КОЖНОЇ речі (хрома проти стелі), а не різниця між ними, і лишається як є.
        _крок = _РЕЄСТР.C["step_min"]
        _кроки = [_нижче(_КО.розкид_осі(ел[id(a[0])], ел[id(b[0])], "L"), _крок)
                  for i, a in enumerate(кольорові) for b in кольорові[i + 1:]]
        _пари = [(ел[id(a[0])], ел[id(b[0])])
                 for i, a in enumerate(кольорові) for b in кольорові[i + 1:]]
        _р = _розмах(кольорові)
        _рст = (_понад(_р, 45) if рівень == "низький" else
                _нижче(_р, 30) if рівень == "високий" else "ні")
        законно, чому_ні = True, None
        if "так" in _кроки:
            законно, чому_ні = False, ("кроку світлоти між кольорами менше за %.0f L* "
                                       "(на рівні вікон, не виміру)" % _крок)
        elif sum(1 for t in кольорові if t[3] >= гучно) > 1:
            законно, чому_ні = False, "гучних кольорів більше за один (хрома ≥ %.0f)" % гучно
        elif _рст == "так":
            законно, чому_ні = False, ("розмах світлоти %s L* при %s контрасті людини (стеля 45 "
                                       "/ підлога 30; на рівні вікон, не виміру)"
                                       % (_слова_розмаху(_р, "понад" if рівень == "низький"
                                                         else "нижче"), рівень))
        elif "невідомо" in _кроки or _рст == "невідомо":
            невідомі["K-PAL-15"] = ([п for п, к in zip(_пари, _кроки) if к == "невідомо"]
                                   + ([(ел[id(t[0])],) for t in кольорові if нв(t)]
                                      if _рст == "невідомо" else []))
    if len(кольорові) >= 2:
        if not законно:
            _дод("K-PAL-15", "hint", "кольори образу не в логіці ваших поєднань",
                 "кольори образу разом не тримають тієї логіки, якою складені ваші поєднання: %s" % чому_ні,
                 "стиліст видає не палітру, а готові трійки; вони будуються кроком світлоти "
                 "(K-COL-01), бюджетом хроми (K-COL-02) і вашим рівнем контрасту",
                 "розвести світлоти кольорів або лишити гучним лише один",
                 [t[0].get("id") for t in кольорові])

    # ── K-PAL-02: АКЦЕНТ БЕРЕТЬСЯ ВІД ОЧЕЙ ПЕРШИМ ────────────────────────────
    # «Повторити колір очей як акцент … завжди доступний, ПЕРШИЙ за порядком»
    # (R-COL-17, Perrett 2023: одяг обирають до райдужки, не до шкіри; 200
    # учасників, T2). У пулі це вже діє рангом рядка, але ранг розв'язує лише
    # НІЧИЮ — а тут питання інше й перевірне: слот, якому СХЕМА дала роль акценту,
    # несе колір із сім'ї очей чи чужий. Мовчимо, коли акцент нейтральний: «нема
    # акценту» — це K-PAL-18, інше правило й інший ремонт.
    очі_дуги_02 = (П["вікна"].get("сім_ї") or {}).get("очі") or []
    if очі_дуги_02:
        def _в_очах(h):
            """Чи тон h лежить бодай в одній дузі сім'ї очей, із запасом `_ЗАПАС_ДУГИ`.

            Дуга буває з переходом через 0° (lo > hi) — тоді перевірка розпадається
            на дві половини; звичайне `lo <= h <= hi` мовчки не впізнавало б
            червоно-пурпурових сімей."""
            for a in очі_дуги_02:
                lo, hi = float(a[0]) - _ЗАПАС_ДУГИ, float(a[1]) + _ЗАПАС_ДУГИ
                if (lo <= h <= hi) if lo <= hi else (h >= lo or h <= hi):
                    return True
            return False
        for r, с, L, C, h, near in кольорові:
            сп = (спец_слоти or {}).get(с)
            if not isinstance(сп, dict) or сп.get("роль") != "акцент":
                continue
            if _в_очах(h):
                continue
            _дод("K-PAL-02", "hint", "акцент не від очей",
                 "слот «%s» несе акцент, а його тон (%.0f°) не з сім'ї ваших очей (%s)"
                 % (с, h, "; ".join("%.0f–%.0f°" % (a[0], a[1]) for a in очі_дуги_02)),
                 "Perrett 2023: одяг обирають до райдужки, не до шкіри; практики ставлять "
                 "перегук очей першим прийомом — це колір, який у людини вже є",
                 "акцент у сім'ї очей (%s) у слоті «%s»"
                 % ("; ".join("%.0f–%.0f°" % (a[0], a[1]) for a in очі_дуги_02), с),
                 [r.get("id")], слот=с)

    # ── K-PAL-05 / 06: ЯКИЙ ПРИЙОМ ОБРАЗ РЕАЛІЗУЄ — І ЧИ ВІН ЇЇ ──────────────
    # Прийоми — оператори з УМОВОЮ («середній/високий контраст», «на м'якій людині
    # обидва приглушені», «для низького контрасту акцент приглушений»). Умова
    # рахувалась у `palettes.прийоми` і вирішувала лише, чи називати прийом
    # доступним; що образ РЕАЛІЗУЄ саме цей прийом і порушує саме його умову, не
    # питав ніхто. Тут образ спершу ВПІЗНАЄТЬСЯ, а тоді перевіряється умова
    # впізнаного — не всіх підряд: інакше на кожен образ висипалось би по чотири
    # hint-и про прийоми, яких у ньому нема.
    if len(кольорові) >= 2:
        дельти = [abs((кольорові[i][4] - кольорові[j][4] + 180) % 360 - 180)
                  for i in range(len(кольорові)) for j in range(i + 1, len(кольорові))]
        м_яка = (П.get("осі") or {}).get("позиція", {}).get("chroma", 0.0) < 0
        if any(нв(t) for t in кольорові):
            # Розведення тону між речами — інтервал на дугах вікон (рядок 141):
            # комплемент стверджується, лише коли ВСЯ пара дуг розведена на ≥150°;
            # «може бути» при зайвих гучних — «без входу». Гучність — кожної речі.
            _т = [(ел[id(a[0])], ел[id(b[0])], _КО.розкид_тону(ел[id(a[0])], ел[id(b[0])]))
                  for i, a in enumerate(кольорові) for b in кольорові[i + 1:]]
            _гучних = sum(1 for t in кольорові if t[3] >= гучно)
            if _гучних > (0 if м_яка else 1):
                if not any(р[2][0] >= 150 for р in _т):
                    if any(р[2][0] < 150 <= р[2][1] for р in _т):
                        невідомі["K-PAL-05"] = [(р[0], р[1]) for р in _т if р[2][0] < 150 <= р[2][1]]
                    дельти = []
                else:
                    дельти = [р[2][0] for р in _т if р[2][0] >= 150]
            else:
                дельти = []
        if any(d >= 150 for d in дельти):
            # K-PAL-05 приглушена комплементарна: «один із двох приглушений або малий;
            # на м'якій людині — обидва приглушені»
            гучних = sum(1 for t in кольорові if t[3] >= гучно)
            треба = 0 if м_яка else 1
            if гучних > треба:
                _дод("K-PAL-05", "default", "комплементарна пара не приглушена",
                     "образ веде комплементарна пара (розведення тону %s%.0f°), а гучних кольорів %d "
                     "при дозволених %d%s%s" % ("щонайменше " if any(нв(t) for t in кольорові) else "",
                                                max(дельти), гучних, треба,
                                                " — ваша палітра м'яка, тут приглушені обидва" if м_яка else "",
                                                "; на рівні вікон, не виміру"
                                                if any(нв(t) for t in кольорові) else ""),
                     "прийом дозволяє комплемент лише коли один із двох приглушений або малий; "
                     "на м'якій людині — обидва (K-COL-03, бюджет хроми)",
                     "приглушити один із двох кольорів або лишити його малою площею",
                     [t[0].get("id") for t in кольорові if t[3] >= гучно])
        # K-PAL-04 (аналогова) ВЕРДИКТУ ТУТ НЕ МАЄ, І ЦЕ РІШЕННЯ, А НЕ ПРОПУСК.
        # Перша редакція давала знахідку «аналогова пара, а прийом не в наборі для
        # вашого контрасту» — і гілка виявилась недосяжною за побудовою: корпус не
        # вимикає аналогову на жодному контрасті («низький/середній; на високому
        # крок ΔL обовʼязковий»), тож умова «прийом недоступний» хибна завжди.
        # А те, що правило справді стверджує над образом — крок світлоти між
        # сім'ями — уже міряє `набір_законний` (K-PAL-15) тим самим `step_min`
        # K-COL-01; другий рядок про те саме число був би не другим правилом, а
        # тим самим удвічі. K-PAL-04 діє там, де має: він ПОРОДЖУЄ аналогові трійки
        # (`palettes.поєднання` з ід="K-PAL-04") і стоїть у пакеті й описі серед
        # прийомів, доступних цій людині, зі своєю умовою.

    # ── K-PAL-06: НЕЙТРАЛІ ПЛЮС ОДИН АКЦЕНТ ──────────────────────────────────
    # «Нейтралі людини + один акцент, перший — сім'я очей; дефолт для високого
    # контрасту; ДЛЯ НИЗЬКОГО АКЦЕНТ ПРИГЛУШЕНИЙ» (K-COL-03; palettehunt; Lamport).
    # ЧОМУ ПОЗА ЛАНЦЮЖКОМ ВПІЗНАВАННЯ ВИЩЕ, І ЦЕ ВИПРАВЛЕННЯ, А НЕ СМАК: той
    # ланцюжок стоїть під `len(кольорові) >= 2`, бо впізнає ВІДНОШЕННЯ між двома
    # кольорами (комплемент, сусідні сім'ї). А цей прийом упізнається якраз
    # ОДНИМ кольоровим на тлі нейтралей — тобто під тією умовою він недосяжний за
    # побудовою. Спіймано пробою: образ «гучна сорочка + три нейтралі» на
    # низькоконтрастній жінці проходив мовчки.
    if len(кольорові) == 1 and len(точки) > 1 and рівень == "низький" and кольорові[0][3] >= гучно:
        акц = кольорові[0]
        _дод("K-PAL-06", "default", "акцент не приглушений на низькому контрасті",
             "образ — ваші нейтралі плюс один акцент, і акцент гучний (хрома %.0f ≥ %.0f) "
             "при низькому контрасті" % (акц[3], гучно),
             "прийом дає для низького контрасту приглушений акцент: гучний на низькому "
             "контрасті читається не як акцент, а як чужа пляма",
             "приглушити акцент або лишити його малою площею",
             [акц[0].get("id")], слот=акц[1])

    # ── K-PAL-07: КОЛОР-БЛОК ВИМКНЕНО НА НИЗЬКОМУ КОНТРАСТІ ─────────────────
    # `palettes.прийоми` вже вирішує, чи прийом доступний ЦІЙ людині («statement
    # або високий контраст; вимкнено на низькому»). Доти це рішення нікуди не
    # їхало. Тут воно судить образ: дві-три кольорові сім'ї у великих слотах — це
    # і є колор-блок, і на низькому контрасті під conventional його нема в наборі.
    ВЕЛИКІ = ("верх", "низ", "сукня", "комплект", "верхній_шар")
    сім_ї_великих = {_сім_я_кута(h) for r, с, L, C, h, near in кольорові if с in ВЕЛИКІ}
    сім_ї_великих.discard(None)
    if len(сім_ї_великих) >= 2 and "колор_блок" not in активні:
        _дод("K-PAL-07", "hint", "колор-блок на низькому контрасті",
             "у великих слотах стоять %d кольорові сім'ї (%s) — це колор-блок, а він "
             "не в наборі прийомів для вашого контрасту під цим наміром"
             % (len(сім_ї_великих), ", ".join(sorted(сім_ї_великих))),
             "Imogen Lamport: колор-блок — виняток («unless heavy colour blocking»), "
             "не дефолт низького контрасту",
             "лишити одну кольорову сім'ю у великих слотах, решту віддати нейтралям",
             [t[0].get("id") for t in кольорові if t[1] in ВЕЛИКІ])

    # ── K-PAL-10: ПРИНТ ПРОТИ ПАЛІТРИ ───────────────────────────────────────
    # Корпус (тема-2:1856): «принт придатний, якщо його домінанта в палітрі і
    # внутрішній контраст ≈ контраст людини». Канал повернувся 16.09, коли річ
    # пулу дістала `колір`/`hex`: домінанту принту система тепер має — це той
    # самий представник кольору речі, яким її й судять скрізь. ДРУГОЇ ПОЛОВИНИ
    # ПРАВИЛА НЕМА І ЦЕ СКАЗАНО ВГОЛОС: внутрішній контраст принту фід не міряє,
    # тому знахідка говорить лише про домінанту й називає межу в `ламається`.
    for r, с, L, C, h, near in поза_палітрою:
        повна = (за_ід or {}).get(r.get("id")) or r
        віз = str(повна.get("візерунок") or "").strip().lower()
        if not віз or віз in ("solid", "однотонний"):
            continue
        _дод("K-PAL-10", "default", "домінанта принту поза палітрою",
             "«%s» має візерунок «%s», а домінанта його кольору поза вікнами вашої палітри"
             % (с or "річ", віз),
             "Lamport 2018: принт придатний, коли його домінанта — ваш колір",
             "принт, домінанта якого в палітрі, або однотонна річ у цьому слоті",
             [r.get("id")], слот=с,
             ламається="внутрішній контраст принту фід не міряє — судиться лише домінанта")

    # ── K-PAL-12: ДРАМАТИЗАЦІЯ М'ЯКОЇ ПАЛІТРИ ───────────────────────────────
    # «М'яку палітру робити драматичною контрастом світлоти, фактурою і блиском,
    # а не хромою» (Lamport 2019, hint). Прийом активний лише під statement при
    # chroma < 0 — і рівно тоді правило має що сказати: якщо образ пішов у гучний
    # колір замість світлоти, він драматизує не тим важелем.
    if "драматизація_м_якої" in активні and len(точки) >= 2:
        гучні = [t for t in кольорові if t[3] >= гучно]
        розмах = _розмах(точки)
        if гучні and _нижче(розмах, 30) == "невідомо":
            невідомі["K-PAL-12"] = [(ел[id(t[0])],) for t in точки if нв(t)]
        if гучні and _нижче(розмах, 30) == "так":
            _дод("K-PAL-12", "hint", "драматизація хромою, не світлотою",
                 "ваша палітра м'яка, а образ драматизується гучним кольором (хрома ≥ %.0f) "
                 "при розмаху світлоти лише %s L*%s"
                 % (гучно, _слова_розмаху(розмах, "нижче"),
                    "; на рівні вікон, не виміру" if any(нв(t) for t in точки) else ""),
                 "Lamport: м'яку палітру робить драматичною контраст світлоти, фактура і блиск, "
                 "а не хрома — гучний колір на м'якій людині читається як чужий, не як сміливий",
                 "розвести світлоти речей або взяти фактуру й блиск замість гучного кольору",
                 [t[0].get("id") for t in гучні])

    # ── K-PAL-13: СИВИНА — ОЧІ СТАЮТЬ ГОЛОВНИМ АКЦЕНТОМ ─────────────────────
    # Прийом активний лише на ахроматичному волоссі (`palettes.прийоми`), і доти
    # це рішення не мало наслідку взагалі: на живому вході батарея не має профілю
    # з сивиною, тож гілка не виконувалась, а якби й виконалась — нікуди не йшла.
    # Тут вона судить: коли волосся не несе температури, єдиний акцент, що лишився
    # від рис, — сім'я очей, і образ без неї біля обличчя втрачає останній перегук.
    if "сивина" in активні:
        очі_дуги = (П["вікна"].get("сім_ї") or {}).get("очі") or []
        біля = [t for t in кольорові if t[5] >= _КО.NEAR_МІН]
        має_очі = any(
            any(((float(a[0]) - _ЗАПАС_ДУГИ <= t[4] <= float(a[1]) + _ЗАПАС_ДУГИ)
                 if float(a[0]) <= float(a[1])
                 else (t[4] >= float(a[0]) - _ЗАПАС_ДУГИ or t[4] <= float(a[1]) + _ЗАПАС_ДУГИ))
                for a in очі_дуги)
            for t in біля)
        if очі_дуги and біля and not має_очі:
            _дод("K-PAL-13", "default", "сивина без акценту від очей",
                 "волосся не несе температури, тому головним акцентом лишаються очі — "
                 "а біля обличчя нема жодного кольору з їхньої сім'ї",
                 "Lamport 2026; Shop My Palette 2026: із сивиною контраст, глибина й хрома "
                 "м'якшають, сірий стає нейтраллю, а очі стають головним акцентом",
                 "колір із сім'ї очей біля обличчя — шарф, верх або сережки",
                 [t[0].get("id") for t in біля])
    # «Без входу» прийомів, що міряють різницю між кольорами речей (рядок 141)
    _що = {"K-PAL-08": "чи збігається контраст образу з вашим (розмах світлоти)",
           "K-PAL-15": "чи тримають кольори образу логіку ваших поєднань (крок і розмах світлоти)",
           "K-PAL-05": "чи веде образ комплементарна пара (розведення тону ≥150°)",
           "K-PAL-12": "чи драматизує образ хромою замість світлоти (розмах світлоти)"}
    for _пр, _пари in невідомі.items():
        if _пари:
            зн.append(_КО.без_входу_кольору(
                _пр, _пари, _що[_пр],
                "%s порівнює колір РЕЧЕЙ між собою — світлоту чи тон — і межа вікна слова "
                "тут лежить по обидва боки порога" % _пр))
    return зн


# ── БЮДЖЕТ ХРОМИ Й ВІДЛУННЯ СУДЯТЬ ОБРАЗ І БЕЗ ВИМІРЯНИХ ПЛОЩ (K-COL-02, K-COL-05)
# ЩО ТУТ БУЛО ДО 17.09.2026, І ЧОМУ ЦЕ НЕ «ЩЕ ОДИН СУДДЯ». Емітенти обох правил є
# від початку і написані правильно — `колір_образу.бюджет_хроми` і
# `колір_образу.відлуння`. Але обидва стоять ЗА ГЕЙТОМ ПЛОЩІ в `суд_образу.review`
# (`площі_є = all(e["площа"] is not None and e.get("джерело_площі") …)`), а свідком
# виміру там навмисно є ПОХОДЖЕННЯ площі, не наявність числа. На живому вході
# `джерело_площі` не ставить ніхто: `composer._у_річ` кладе заглушку 1/N, а
# `outfit.площі_з_геометрії` рахує площу лише з довжин виробу, яких фід не дає.
# ВИМІРЯНО НА `каталог_повний.xml` (10 770 офферів, 17.09.2026): речей із
# походженням площі — 0, тобто гейт закритий на 100 % образів, і два правила з
# корпусною силою `strong`/`default` не сказали жодного слова жодного разу.
# ГЕЙТ ПЛОЩІ НЕ ЧІПАЄТЬСЯ, І ЦЕ НАВМИСНО: він захищає від вигаданої площі, і саме
# він поіменно ловив хибні вердикти (заглушка 1/6 додавала три знахідки й ковтала
# одну справжню). Змінено інше: ТА ЧАСТИНА ОБОХ ПРАВИЛ, ЯКІЙ ПЛОЩА НЕ ПОТРІБНА,
# судить зібраний образ тут — з кольору, який ВИМІРЯНО, і зі слота, який названо.
#   K-COL-02 — «≤1–2 високонасичених елементи на образ, РАХУЮЧИ волосся й оправу»:
#     це ЛІЧБА, і площа в ній потрібна лише щоб відсіяти ювелірний масштаб. Тут
#     його відсіює слот (набір `_ЮВЕЛІРНІ`), а не поріг площі.
#   K-COL-05 — «акцент або повторюється, або є свідомим фокусом»: лічба ЗОН, і
#     площа потрібна лише як міра «малості» сироти. Тут її замінює КЛАС СЛОТА
#     (великі слоти проти акцентних) — і ця заміна названа в `ламається`.
# ЧОГО ТУТ НЕМА: другої половини K-COL-02 («конфлікт хром: два гучні кольори
# СПІВМІРНОЇ ПЛОЩІ») і порогу `focus_area` у K-COL-05. Обидві стоять на порівнянні
# площ, а не на їх наявності, і вигадати їх зі слота не можна — вони лишаються в
# `колір_образу`, за гейтом площі, і оживуть разом із ним.
# ДУБЛЯ НЕ БУДЕ: коли площі колись зміряються, обидва емітенти дадуть по знахідці
# того самого правила, а `знахідки_вердикту` зливає їх у ОДИН рядок за `правило`,
# лишаючи найсильнішу — тобто ту, що стоїть на вимірі, а не на слоті.
_ВЕЛИКІ_СЛОТИ = ("верх", "низ", "сукня", "комплект", "верхній_шар")
# Ювелірний масштаб — слотом, бо площі нема. Той самий поділ, що вже стоїть у
# `колір_образу.SLOT_NEAR_FALLBACK` (сережки/каблучка/годинник) і в
# `МЕТАЛ_ЮВЕЛІРНА_ПЛОЩА`: метал у цих слотах бюджету хроми не витрачає.
_ЮВЕЛІРНІ = ("прикраси", "сережки", "намисто", "кольє", "каблучка", "браслет",
             "годинник", "брошка")
_СУСІДНІ_ТОНИ = 45.0        # той самий, що `колір_образу.відлуння.СУСІДНІ`


def бюджет_і_відлуння(речі, F=None, за_ід=None, фокус=None):
    """[знахідки] K-COL-02 (бюджет хроми) і K-COL-05 (відлуння) над ЗІБРАНИМ образом.

    Площі не потрібно: перше правило рахує ГУЧНІ елементи, друге — ЗОНИ. `F` —
    риси особи (`волосся*`, `оправа`): корпус K-COL-02 прямо каже «counting hair,
    counting eyewear frames», і без них бюджет рахувався б не за правилом.

    K-COL-05 порівнює тон РЕЧЕЙ і тому судить лише вимір (рядок 141): речі, чий
    колір — центр вікна слова, групуються на рівні вікон, а висновок, що на них
    не тримається, іде записом «без входу» з названим полем (`без_входу_кольору`).
    """
    import реєстр_правил as _РЕЄСТР, palettes as _ПЛ, колір_образу as _КО
    гучно = _РЕЄСТР.C["hi_C"]
    точки = _кольори_образу(речі, за_ід)
    if not точки:
        return []
    зн = []

    def _дод(правило, сила, ярлик, суть, чому, зняло_б, речі_, ремонт=None, **решта):
        """Додає знахідку ПРАВИЛА КОЛЬОРУ до `зн` з повним набором полів судді.

        Відмінність від однойменної в прийомах палітри одна й навмисна: `ремонт`
        тут окремий аргумент і падає на `зняло_б`, коли його не передали. «Що зняло
        б знахідку» і «що зробити» збігаються не завжди, але там, де збігаються,
        два однакові рядки руками розходяться на наступній правці."""
        зн.append(dict(правило=правило, сила=сила, сила_нп=_СИЛА_НП[сила], впевненість=1.0,
                       регістр=_РЕЄСТР.регістр(правило, сила), бік="код",
                       сила_нп_джерело="корпусна сила правила кольору (тема-4 §K-COL)",
                       речі=[x for x in речі_ if x], ярлик=ярлик, суть=суть, чому=чому,
                       ремонт=ремонт or зняло_б, що_зняло_б=зняло_б, **решта))

    # ── K-COL-02: БЮДЖЕТ ХРОМИ ────────────────────────────────────────────────
    # Метал у ювелірному слоті з бюджету виходить із тієї самої причини, що в
    # `колір_образу.бюджет_хроми`: золотий ланцюжок — не колірний блок. Там межу
    # тримає площа, тут — слот.
    гучні = [(r, с) for r, с, L, C, h, near in точки
             if C >= гучно and not (с in _ЮВЕЛІРНІ and _ПЛ.метал_речі(_lab_з(L, C, h), с))]
    бюджет = [("«%s»" % (r.get("назва") or r.get("id") or с)) for r, с in гучні]
    особа_гучна = []
    for k, f in (F or {}).items():
        if not isinstance(f, dict) or str(k).startswith("_"):
            continue
        if str(k).startswith("волосся") and (f.get("C") or 0) >= гучно:
            особа_гучна.append("волосся (C*%.0f)" % f["C"])
        if k == "оправа" and (f.get("C") or 0) >= гучно:
            особа_гучна.append("оправа (C*%.0f)" % f["C"])
    разом = len(гучні) + len(особа_гучна)
    if разом > 2:
        _дод("K-COL-02", "strong", "понад бюджет хроми",
             "високонасичених елементів %d при стелі 2: %s — решта образу не встигає бути тлом"
             % (разом, ", ".join(бюджет + особа_гучна)),
             "корпус рахує не кольори, а ГУЧНІ елементи, і волосся та оправа входять у "
             "бюджет нарівні з речами: вони теж приобличчевий акцент, тільки постійний",
             "лишити один гучний як фокус; решту взяти приглушеними версіями тієї самої "
             "сім'ї або нейтралями (K-COL-03: нейтралі + акцент)",
             [r.get("id") for r, _ in гучні], поріг=2, вимір=разом,
             ламається="без виміряних площ дрібний аксесуар важить у лічбі як велика річ — "
                       "поріг ювелірного масштабу тут тримає СЛОТ, а не частка образу")

    # ── K-COL-05: ВІДЛУННЯ ────────────────────────────────────────────────────
    # Групування за дугою 45°, а не за ім'ям сім'ї, — те саме рішення й з тієї
    # самої причини, що в `колір_образу.відлуння`: сусідні тони (200°, 230°, 255°)
    # читаються як ОДИН акцент, а тверді межі сімей рвали їх на «сироту» й «пару».
    кольорові = [(r, с, L, C, h) for r, с, L, C, h, near in точки
                 if not _нейтральний_тон(h, C, L) and not _ПЛ.метал_речі(_lab_з(L, C, h), с)]
    # ── ГРУПУЄТЬСЯ ЛИШЕ ВИМІР (23.09.2026, рядок 141) ─────────────────────────
    # Тон речі зі слова — центр дуги вікна, а не тон речі: дві «м'ятні» речі мали
    # той самий кут, і «сирота» чи «пара» над ними була наслідком побудови. Тому
    # жадібне групування — те саме, що доти, — іде лише по ВИМІРАХ; речі, чий колір
    # не вимір (`колір_образу.не_вимір`), судяться попарно НА РІВНІ ВІКОН
    # (`поруч_за_тоном`): «так» — уся дуга в межах 45°, «ні» — жодна її точка не
    # дістає, інакше «невідомо». Висновок, що стоїть на «невідомо», не робиться ні в
    # той, ні в інший бік: він іде записом «без входу» з названим полем. Образ, у
    # якому всі кольори — виміри, судиться рівно як доти.
    ел = {id(t): _елемент_точки(t, за_ід) for t in кольорові}
    невиміряні = [t for t in кольорові if _КО.не_вимір(ел[id(t)])]
    _нев = {id(t) for t in невиміряні}
    поруч = lambda a, b: _КО.поруч_за_тоном(ел[id(a)], ел[id(b)], _СУСІДНІ_ТОНИ)
    групи = []
    for t in sorted([t for t in кольорові if id(t) not in _нев], key=lambda t: -t[3]):
        for g in групи:
            d = abs(g[0][4] - t[4]); d = min(d, 360 - d)
            if d <= _СУСІДНІ_ТОНИ:
                g.append(t); break
        else:
            групи.append([t])
    невідомі = []

    def _сирота(члени, слот, назва, вікна):
        """Знахідка «акцент-сирота» (чи «у фокусі») над групою `члени` в одному слоті."""
        свідомий = bool(фокус) and слот in фокус
        _дод("K-COL-05", "hint" if свідомий else "default",
             "акцент-сирота" if not свідомий else "акцент у оголошеному фокусі",
             "акцент «%s» стоїть в одному акцентному слоті («%s») і більше ніде — "
             "око не знаходить наміру%s" % (назва, слот, "; на рівні вікон, не виміру"
                                           if вікна else ""),
             "гештальтний повтор: колір, який не відлунює у другій рознесеній зоні і "
             "не оголошений фокусом, читається як шум, а не як хід"
             + ("; колір речі зі слова (центр вікна не судиться), і %s" % вікна
                if вікна else ""),
             ("фокусна зона оголошена («%s») — акцент легітимний як пуант" % слот
              if свідомий else
              "повторити цей колір у другій рознесеній зоні (взуття ↔ сумка ↔ шарф ↔ "
              "прикраси) АБО оголосити цю зону фокусом АБО прибрати"),
             [t[0].get("id") for t in члени], слот=слот, вимір=1, поріг=2,
             ламається="без виміряних площ «малість» сироти міряє КЛАС СЛОТА, не частка "
                       "образу: гучна сумка й дрібна брошка тут важать однаково, а "
                       "великий слот із того самого кольору правило мовчки пропускає")

    for g in групи:
        зони = {t[1] for t in g}
        назва = _сім_я_кута(g[0][4]) or "тон ~%d°" % round(g[0][4])
        так = [u for u in невиміряні if поруч(u, g[0]) == "так"]
        може = [u for u in невиміряні if поруч(u, g[0]) == "невідомо"]
        if len(зони) == 1:
            слот = next(iter(зони))
            if слот in _ВЕЛИКІ_СЛОТИ:
                continue            # велика поверхня — це не сирота-акцент, а сам образ
            if any(u[1] != слот for u in так):
                continue            # відлуння є напевно: уся дуга невиміряної речі в межах 45°
            if any(u[1] != слот for u in може):
                невідомі += [(ел[id(g[0])], ел[id(u)]) for u in може if u[1] != слот]
                continue
            _сирота(g, слот, назва, "")
            continue
        зони_так = зони | {u[1] for u in так}
        if len(зони_так) > _РЕЄСТР.C["echo_max"]:
            _дод("K-COL-05", "soft", "відлуння понад стелю",
                 "акцент «%s» повторено у %d зонах — повтор перестає читатись як намір і "
                 "стає уніформою%s" % (назва, len(зони_так), "; на рівні вікон, не виміру"
                                      if так else ""),
                 "стеля відлуння: 4+ носії одного кольору — це вже matchy, а не перегук"
                 + ("; на рівні вікон: %d із них — речі зі слова, чия дуга вся в межах 45°"
                    % len(так) if так else ""),
                 "лишити 2–3 носії, решту перевести в нейтраль",
                 [t[0].get("id") for t in g + так], вимір=len(зони_так),
                 поріг=_РЕЄСТР.C["echo_max"],
                 ламається="тональна колона одного кольору — інша схема (K-COL-03 §2), не "
                           "відлуння; схема образу сюди не доїжджає, тому стеля тут груба")
        elif len(зони_так | {u[1] for u in може}) > _РЕЄСТР.C["echo_max"]:
            невідомі += [(ел[id(g[0])], ел[id(u)]) for u in може]
    # Невиміряний акцент сам: сирота лише тоді, коли тон жодної іншої речі не
    # дістає 45° на всьому його вікні; відлуння — коли хоч одна дістає цілою дугою.
    for u in невиміряні:
        if u[1] in _ВЕЛИКІ_СЛОТИ:
            continue
        стани = [(t, поруч(u, t)) for t in кольорові if t is not u and t[1] != u[1]]
        if any(в == "так" for _, в in стани):
            continue
        if all(в == "ні" for _, в in стани):
            _сирота([u], u[1], (_КО.не_вимір(ел[id(u)]) or {}).get("слово")
                    or _сім_я_кута(u[4]) or "тон ~%d°" % round(u[4]),
                    "тон жодної іншої кольорової речі не дістає 45° на всьому вікні"
                    if стани else "інших кольорових речей в образі нема — відлунювати нема чому")
            continue
        невідомі += [(ел[id(u)], ел[id(t)]) for t, в in стани if в == "невідомо"]
    if невідомі:
        зн.append(_КО.без_входу_кольору(
            "K-COL-05", невідомі, "чи відлунює акцент у другій зоні",
            "K-COL-05 групує акценти за тоном (дуга 45°): сирота — акцент без другого "
            "носія, matchy — понад три носії; обидва висновки — про тон речі, а не про "
            "середину дуги слова"))
    return зн


def _lab_з(L, C, h):
    """(L, C, h) → Lab. Локальна дрібниця: `palettes.метал_речі` питає Lab, а тут
    колір уже розкладений на осі, і збирати його назад через `colorspace` двічі
    в одному циклі дорожче, ніж порахувати два косинуси."""
    import math as _м
    r = _м.radians(float(h))
    return (float(L), float(C) * _м.cos(r), float(C) * _м.sin(r))


def _елемент_точки(t, за_ід=None):
    """Точка `_кольори_образу` (річ, слот, L, C, h, …) → елемент для помічників
    `колір_образу` (рядок 141): lab, провенанс кольору (`колір_не_вимір` із запису
    КАТАЛОГУ — рядок пулу його не несе), id, назва, слот."""
    r = t[0]
    повна = (за_ід or {}).get(r.get("id")) or r
    return dict(lab=_lab_з(t[2], t[3], t[4]), колір_не_вимір=повна.get("колір_не_вимір"),
                річ=r.get("id"), назва=повна.get("назва") or r.get("назва"), слот=t[1])


def акцент_образу(речі, спец_слоти, кандидати=None, за_ід=None):
    """[знахідки] — де роль «акцент» призначена, але хроми в образі нема.

    `за_ід` — id → запис КАТАЛОГУ. Він тут обов'язковий: записи пулу, які їдуть
    до моделі, несуть лише назву, ціну й словесну зону, БЕЗ `lab`. Рахувати
    хрому по них означало б діставати None на кожній речі й через це завжди
    списувати провал на каталог — тобто зробити звинувачення сталим, а перевірку
    невідрізненною від заглушки. Спіймано першим же прогоном: «у пулі НЕМА
    жодної речі з хромою» стояло і там, де речі були.
    """
    if not спец_слоти:
        return []
    за_слотом = {}
    for r in речі:
        за_слотом.setdefault(r.get("слот"), r)
    зн = []
    # ключі на «_» — службові (напр. `_схема`), не слоти. Без цього фільтра
    # рядок схеми потрапляв у цикл як «слот» і валив перевірку AttributeError.
    # СХЕМА ВЕЛИКИХ ПОВЕРХОНЬ (рядок 133): сім'ї схеми вільно лягають на будь-яку велику
    # річ (сім'я-верх може стояти і на жакеті), тож «акцент саме в цьому слоті» тут хибна
    # вимога: на дощовому образі вона казала «акцент на жакеті», поки K-COL-03 казав
    # «заміни верх» — дві знахідки, що суперечать одна одній. Схему цілком судить K-COL-03
    # (`palette.обіцянка_великих`), покомпонентний акцент мовчить.
    if спец_слоти.get("_поверхні") == "великі":
        return []
    # траурна нагода зі схемою коду (рядок 154): акцентна роль тут не проситься
    if спец_слоти.get("_траур"):
        return []
    акцентні = [(с, сп) for с, сп in спец_слоти.items()
                if not str(с).startswith("_") and isinstance(сп, dict)
                and сп.get("роль") == "акцент" and сп.get("C")]
    for с, сп in акцентні:
        r = за_слотом.get(с)
        if r is None:                      # слота в образі нема — це не «зник акцент»
            continue
        C = _хрома(r)
        if C is None:                      # колір речі не виміряний: мовчати чесніше,
            continue                       # ніж рахувати невимір за провал
        Cmin = float(сп["C"][0])
        if C >= Cmin:
            continue
        # чи взагалі БУЛО з чого взяти акцент у цьому слоті
        пул = ((кандидати or {}).get(с) or [])
        повні = [(за_ід or {}).get(x.get("id")) or x for x in пул]
        мали = [x for x in повні if (_хрома(x) or 0.0) >= Cmin]
        if мали:
            зн.append(dict(правило="K-PAL-18", сила="soft", бік="код",
                           слот=с, ярлик="акцент зник",
                           суть=("схема «%s» дала слоту «%s» роль акценту (хрома від %.0f), "
                                 "а річ у ньому має %.0f — у пулі було %d речей із хромою"
                                 % (спец_слоти.get("_схема", "?"), с, Cmin, C, len(мали))),
                           чому="вибір проти власної спеки: акцент був доступний і не взятий",
                           що_зняло_б="річ із хромою ≥ %.0f у слоті «%s»" % (Cmin, с)))
        else:
            зн.append(dict(правило="K-PAL-18", сила="hint", бік="дані",
                           слот=с, ярлик="акценту не було з чого взяти",
                           суть=("схема «%s» вимагає акценту в слоті «%s» (хрома від %.0f), "
                                 "але в пулі цього слота НЕМА жодної речі з такою хромою"
                                 % (спец_слоти.get("_схема", "?"), с, Cmin)),
                           чому="дефіцит каталогу, не вибір моделі: звинувачувати модель тут — "
                                "помилка атрибуції",
                           що_зняло_б="джерела з кольоровими речами в цьому слоті"))
    # ЗВЕДЕНОЇ ЗНАХІДКИ («жоден акцентний слот не несе хроми») ТУТ НЕМА НАВМИСНО.
    # Вона була написана й ВИДАЛЕНА того ж прогону: `слот=None` не чіпляється до
    # жодної речі, тому граф її відкидає, і назовні їхали дві знахідки з трьох.
    # Правило, яке виконується, лишає слід і не доходить до людини, — рівно той
    # третій ярус, який тут заборонено. Дві послотові знахідки кажуть усе те саме
    # й доїжджають.
    return зн


def _хрома(r):
    """C* речі або None. None — це «не виміряно», і воно не рахується за провал."""
    lab = r.get("lab")
    if not lab and r.get("hex"):
        try:
            import colorspace as _КС
            lab = _КС.hx(r["hex"])
        except (TypeError, ValueError, AttributeError):
            lab = None
    if not lab or len(lab) < 3:
        return None
    return (float(lab[1]) ** 2 + float(lab[2]) ** 2) ** 0.5


def _спорт_чи_дім(сценарій):
    """Нагода, у якій сумка, третя річ і пальто не обов'язкові: спорт, пляж, дім.

    Одне місце для двох читачів (рядок 146): `структура_образу` ставить за ним
    блокери повноти, `повнота_образу.повнота_набору` — рядок «візьми своє»."""
    _наг = " ".join(str((сценарій or {}).get(k) or "")
                    for k in ("нагода", "місце", "подія", "дрес_код")).lower()
    return any(w in _наг for w in ("спорт", "трен", "йога", "біг", "пляж", "вдома", "домаш", "дім"))


def структура_образу(речі, слоти_пулу=None, сценарій=None, верхні=None):
    """Блокери означення образу: по одній речі на слот, і є сукня або верх+низ.

    Це не правило стилю — це те, чим образ є. Дві пари взуття в одному образі
    ніхто не носить; образ без верху й низу (і без сукні) — це не образ, а
    аксесуари. Верхній шар, взуття, сумка й прикраси можуть бути відсутні —
    їх відсутність не робить образ не-образом. ВИНЯТОК (рядок 146): нижче +10 °C
    верхній шар — умова повноти, як взуття й сумка (`суд_погода.пальтова_смуга`),
    коли пул має чим його закрити: `верхні` — речі пулу, що в образі стануть
    верхнім шаром (`суд_погода.пальта_пулу`); None — пул невідомий, блокера нема.

    `слоти_пулу`: id → множина слотів, у яких ця річ стояла в пулі. ДВОСЛОТОВІ
    речі (кардиган: каталожний слот «верхній_шар», а в пулі і «верх») мусять
    рахуватись тим слотом, у якому вони справді стоять в образі: без цього
    кардиган, узятий як верх, дав би хибний блокер «нема верх» (спіймано
    пробою 02.09). Правило: спершу кожна річ бере свій каталожний слот; коли
    обов'язковий слот лишається порожнім, його закриває річ, що мала його в
    пулі, — і тоді вона вже не рахується у своєму каталожному."""
    import collections as _c, composer as _КМ, graph as _ГР
    б = []
    обов = [s for s in _ГР.СЛОТИ if s not in _КМ.СЛОТИ_НЕОБОВЯЗКОВІ]
    # ключ — ПОЗИЦІЯ речі, не id: речі без id (тести, вигадані руками 3/4) не
    # мають злипатись в одну
    призн = [(r.get("слот") or "?") for r in речі]
    # ЦІЛА РІЧ НЕ ПЕРЕПРИЗНАЧАЄТЬСЯ В ПОЛОВИНУ (04.09.2026, спіймано наскрізним
    # прогоном): комплект має в пулі і «верх», і «низ» (слоти_альт), і цикл нижче
    # ставив його у порожній «верх» — після чого «низ» лишався порожнім, і суддя
    # блокував «нема низу» рівно той образ, у якому низ є. Сукня й комплект
    # закривають обидва обов'язкові слоти собою і в перепризначення не входять.
    ЦІЛІ = ("сукня", "комплект")
    if слоти_пулу:
        зайняті = set(призн)
        # (внутрішньої перевірки «річ у ЦІЛІ — пропустити» тут нема навмисно: зовнішня
        # умова вже не пускає в перепризначення жоден образ із цілою річчю, і мутант
        # показав, що внутрішня була мертвою — прибрано того ж дня)
        if not (set(призн) & set(ЦІЛІ)):
            for s in обов:
                if s in зайняті:
                    continue
                for i, r in enumerate(речі):
                    if s in (слоти_пулу.get(str(r.get("id"))) or ()) and призн[i] != s:
                        призн[i] = s; зайняті.add(s); break
