# -*- coding: utf-8 -*-
"""каталог_розбір_сусіди.py — РОЗБІР МОДЕЛІ ОДИН РАЗ НА СУСІДІВ (наряд 5.4-С; менеджер 25.10, п.4а).

ЩО РОБИТЬ. Каталог містить варіанти однієї моделі як окремі речі: ті самі назва, опис і картка, інші лише
колір і розмір. Повний розбір (~32 с на річ) на них повторює ті самі відповіді. Тут:
  · СУСІДИ — речі однієї крамниці й групи прогону, у яких рівні ВСІ слова, що бачить модель (`КР.вхід`), крім
    полів кольору й розміру крамниці. Код порівнює рядки; слів не тлумачить (п.12). Перший член — ПРЕДСТАВНИК
    (донор): його розбирають повністю; решта беруть його відповідь, крім кольору.
  · КОЛІР СУСІДА визначає модель: короткий виклик на колір картки (`ОГОЛОШЕННЯ`) — на кожне унікальне значення
    кольорових полів один (режим «значення») або на річ (режим «річ», з назвою). Колір сусіда, рівний кольору
    донора, виклику не потребує. Код слів кольору не зіставляє.
  · СИНТЕЗ — відповідь донора з трьома полями кольору, замінені відповіддю короткого виклику. Далі її читає
    той самий `зібрати` проти ВЛАСНОГО тексту сусіда: цитата, якої в його тексті нема (наприклад з розміру чи
    кольору донора), лишає "unknown" з причиною `invented`, як і в повного розбору.

ЧОГО ТУТ НЕМА. Викликів моделі (їх робить `каталог_розбір_прогін.py`), порівняння з повним розбором (проби
`проби/каталог_сусіди_*.py`) і чужих полів: `color_from` код виводить сам з місця цитати.

ПОЛЯ КОЛЬОРУ Й РОЗМІРУ — технічна межа за ІМЕНЕМ ключа картки, виміряна по каталогу (`поля_крамниці`): ключі,
чиє значення є самим кольором або самим розміром варіанта. Ключі-відгуки («~5 | 2 відгука залишити відгук
колір») та мірки («~36 розмір») в списку не стоять: вони лишаються в ключі, тож роблять речі несусідами —
помилка в бік більшого розбору, не меншого.
"""
import hashlib
import json
import os
import sys

ТУТ = os.path.dirname(os.path.abspath(__file__))
if ТУТ not in sys.path:
    sys.path.insert(0, ТУТ)

import збирач_промптів as ЗП         # noqa: E402
import каталог_розбір as КР          # noqa: E402
import протокол as _ПР               # noqa: E402

ПОЛЯ_КОЛЬОРУ = frozenset(("колір", "~колір", "~color", "~колір взуття", "~колір сумки", "~оберіть колір",
                          "~цвет"))
ПОЛЯ_РОЗМІРУ = frozenset(("розміри", "розмір", "~розмір", "~size", "~розмір:", "~оберіть розмір",
                          "~таблиця розмірів розмір"))
# Поля відповіді, що залежать від кольору картки. `color_from` модель не пише — `зібрати` виводить його з
# місця цитати `color_main`.
КОЛІРНІ_ПОЛЯ = ("color_main", "color_extra", "color_why")
РЕЖИМИ = ("значення", "річ")
ЗАДАЧА_КОЛЬОРУ = "CATALOG_COLOR_V1"
ІМ_СХЕМИ_КОЛЬОРУ = "catalog_color_v1"
# Найдовша правдоподібна відповідь: цитата 120 знаків на color_main і 4 color_extra плюс why — ~900 знаків,
# ~350 токенів; 500 лишають запас, а обрізана відповідь стає видною (не JSON → повтор).
МАКС_ТОКЕНІВ_КОЛЬОРУ = 500


def розбити(o):
    """(ключ, колір): `ключ` — рядок, рівний у речей-сусідів (крамниця + усе, що бачить модель, крім полів
    кольору й розміру); `колір` — {ключ картки: значення} кольорових полів цієї речі."""
    в = dict(КР.вхід(o))
    пар = dict(в.get("params") or {})
    колір = {к: пар.pop(к) for к in sorted(пар) if к in ПОЛЯ_КОЛЬОРУ}
    for к in [к for к in пар if к in ПОЛЯ_РОЗМІРУ]:
        del пар[к]
    if "params" in в or пар:
        в = dict(в, params=пар)
    return json.dumps([o.get("магазин"), в], sort_keys=True, ensure_ascii=False), колір


def розподіл(пари, готова, повна):
    """{позиція сусіда: позиція донора} для речей `пари` [(група, офер)], що ще не розібрані.

    `готова(поз)` — річ уже має відповідь у теці; `повна(поз)` — відповідь повного розбору, не синтез.
    Група сусідів — крамниця, група прогону й рівний ключ; менше двох членів — сусідів нема. Донор —
    перший член із повним розбором, що вже лежить у теці, інакше перший ще нерозібраний. Розібрані члени
    не міняються."""
    групи = {}
    for поз, (група, o) in enumerate(пари):
        групи.setdefault((група, розбити(o)[0]), []).append(поз)
    вих = {}
    for члени in групи.values():
        чекають = [п for п in члени if not готова(п)]
        if len(члени) < 2 or not чекають:
            continue
        донор = next((п for п in члени if готова(п) and повна(п)), чекають[0])
        # Річ без полів кольору колірного виклику не має (нема що цитувати) — іде повним розбором.
        вих.update({п: донор for п in чекають if п != донор and розбити(пари[п][1])[1]})
    return вих


def _скелет_кольору():
    """V5-взірець кольору з того самого конструктора, що й повний розбір."""
    return КР.скелет_полів(КОЛІРНІ_ПОЛЯ)


def схема_кольору():
    """JSON Schema короткої V5-відповіді, побудована тим самим конструктором, що повна."""
    return КР.схема_полів(КОЛІРНІ_ПОЛЯ)


_ПРАВИЛА_КОЛЬОРУ = КР.правила_полів(КОЛІРНІ_ПОЛЯ)
_ПОЛЕ_КАРТКИ = ЗП.Поле("params", "colour fields of the shop card: key and value", треба=True)
ОГОЛОШЕННЯ = {
    режим: ЗП.Оголошення(
        задача=ЗАДАЧА_КОЛЬОРУ,
        роль=("You read the colour fields of one shop item and write its colours as codes, each backed by "
              "a quote from those fields."),
        вхід=(((ЗП.Поле("name", "the shop's name of the item", треба=True),) if режим == "річ" else ())
              + (_ПОЛЕ_КАРТКИ,)),
        правила=_ПРАВИЛА_КОЛЬОРУ, вихід=ЗАДАЧА_КОЛЬОРУ, межі=("лише_вхід",),
        скелет=_скелет_кольору(), мова_промпту="en")
    for режим in РЕЖИМИ}


def колір_дані(o, режим):
    """Вхід короткого виклику цієї речі: поля кольору картки (і назва в режимі «річ»)."""
    колір = розбити(o)[1]
    return dict(({"name": o.get("назва")} if режим == "річ" else {}), params=колір)


def колір_промпт(o, режим):
    """Повідомлення короткого виклику — рядок JSON, як у повного (`json.dumps` без відступів)."""
    return json.dumps(ЗП.зібрати(ОГОЛОШЕННЯ[режим], колір_дані(o, режим)), ensure_ascii=False)


def колір_ключ(o, режим):
    """Ім'я кешу короткого виклику. «значення»: одне на унікальне значення кольорових полів на весь
    каталог (крамниця й назва до запиту не входять); «річ»: одне на річ (id у ключі), тож однакові
    кольори двох речей — два виклики."""
    основа = колір_промпт(o, режим) + ("\n" + o["id"] if режим == "річ" else "")
    return "%s_%s" % (режим, hashlib.sha1(основа.encode("utf-8")).hexdigest()[:12])


def колір_придатний(текст):
    """Коротку відповідь пускає колірна V5-схема й розбирає той самий `_з_рядків`, що повну."""
    к = _ПР.розібрати_json((текст or "").replace(КР.ВСТАВКА, ""))
    if not isinstance(к, dict) or not КР.за_схемою(к, схема_кольору()):
        return False
    КР._з_рядків(к)
    return True


def синтез(відп_донора, відп_кольору=None, назва_донора=None, назва_речі=None, порожні_features=True):
    """Текст відповіді сусіда: відповідь донора, де `КОЛІРНІ_ПОЛЯ` замінені полями `відп_кольору`; без
    `відп_кольору` — відповідь донора як є (колір сусіда рівний кольору донора). None — відповідь донора або
    короткого виклику не розібралась як JSON-об'єкт із потрібними ключами."""
    об = _ПР.розібрати_json((відп_донора or "").replace(КР.ВСТАВКА, ""))
    if not isinstance(об, dict) or not КР.за_схемою(
            об, КР.схема_відповіді(назва_донора, порожні_features)):
        return None
    if відп_кольору is not None:
        if not колір_придатний(відп_кольору):
            return None
        к = _ПР.розібрати_json(відп_кольору.replace(КР.ВСТАВКА, ""))
        колір = к[КР.КОДИ].split(";")
        пункти = [п for п in об[КР.КОДИ].split(";")
                  if п.partition("=")[0] not in КОЛІРНІ_ПОЛЯ]
        об[КР.КОДИ] = ";".join(пункти + колір)
    return (json.dumps(об, ensure_ascii=False)
            if КР.за_схемою(об, КР.схема_відповіді(
                назва_речі or назва_донора, порожні_features)) else None)
