def _копія():
    """Тимчасова тека з усіма джерелами. Великий каталог — символьним посиланням:
    10 МБ копіювати на кожен мутант нема сенсу, а гейти його лише читають."""
    тека = tempfile.mkdtemp(prefix="мутант_")
    for маска in ДЖЕРЕЛА:
        for ш in glob.glob(os.path.join(ТУТ, маска)):
            ціль = os.path.join(тека, os.path.basename(ш))
            if ш.endswith(".xml") and os.path.getsize(ш) > 1_000_000:
                os.symlink(ш, ціль)
            else:
                shutil.copy(ш, ціль)
    return тека


def прогнати(від=0, до=None):
    зріз = МУТАНТИ[від:(len(МУТАНТИ) if до is None else до)]
    провал = 0
    for файл, було, стало, гейт in зріз:
        тека = _копія()
        try:
            ш = os.path.join(тека, файл)
            s = open(ш, encoding="utf-8").read()
            if було not in s:
                print("  ⚠ мутант не наклався:", файл, "|", гейт); провал += 1; continue
            open(ш, "w", encoding="utf-8").write(s.replace(було, стало, 1))
            r = subprocess.run([sys.executable, "гейти_нові.py"], cwd=тека,
                               capture_output=True, text=True, timeout=900)
            червоні = [l for l in r.stdout.splitlines() if "✗" in l]
            влучив = any(гейт[:40] in l for l in червоні)
            print(("  ✓ мутант «%s» → гейт червоний" if влучив else "  ✗ мутант «%s» гейта НЕ зачервонив")
                  % гейт[:52])
            if not влучив:
                провал += 1
                print("     червоні були:", [l.strip()[:70] for l in червоні] or "жодного")
                if r.returncode and r.stderr.strip():
                    print("     stderr:", r.stderr.strip().splitlines()[-1][:120])
        finally:
            shutil.rmtree(тека, ignore_errors=True)
    print("\nмутантів провалено: %d з %d" % (провал, len(зріз)))
    return провал


if __name__ == "__main__":
    від = int(sys.argv[1]) if len(sys.argv) > 1 else 0
    до = int(sys.argv[2]) if len(sys.argv) > 2 else None
    sys.exit(1 if прогнати(від, до) else 0)
