def покриття(речі, поля):
    """[(поле, речей, %)] — «є» це NOT None: `False` — оголошене «нема», тобто вхід."""
    ряд = [(п, sum(1 for р in речі if р.get(п) is not None)) for п in поля]
    return sorted([(п, n, (100.0 * n / len(речі)) if речі else 0.0) for п, n in ряд],
                  key=lambda x: -x[1])


def param_покриття(offers, ключі):
    ряд = [(к, sum(1 for o in offers
                   if str((o.get("параметри") or {}).get(к) or "").strip()))
           for к in ключі]
    return sorted([(к, n, (100.0 * n / len(offers)) if offers else 0.0) for к, n in ряд],
                  key=lambda x: -x[1])


def _ід_знахідок(вих):
    ід = set()
    for відро in ("ворота", "преференції", "питання", "ремонти", "команди"):
        for з in (вих.get(відро) or []):
            if isinstance(з, dict) and з.get("правило"):
                ід.add(з["правило"])
    return ід


def прогін_правил(речі_верху):
    """Скільки РЕАЛЬНИХ речей верхнього шару виводять кожне правило теми-11."""
