#   · КРИСИ КАПЕЛЮХА. Носія в профілі тіла НЕМА взагалі: криси — це виступ на рівні
#     обличчя, і порівнюються вони з шириною ОБЛИЧЧЯ, якої фронтальний профіль тіла не
#     містить. Мовчазне повернення None видавало б «перевірено» за «нема входу», тому
#     випадок винесено у `БЕЗ_ВХОДУ` під K-HAT-02.
НОСІЇ_КРАЮ = {
 # K-ACC-04 — ЦЕ ВОНО. Правило було РЕАЛІЗОВАНЕ й цитоване як K-EDG-01, тобто під
 # ідентифікатором свого узагальнення. Наслідок вузький, але точний: гейт «правило з
 # корпусу доходить до виходу» рахував K-ACC-04 відсутнім, хоч воно працює, а слід
 # звʼязував рішення з узагальненням замість іменованого правила. Обидва ID тепер
 # у сліді: K-EDG-01 як механізм, K-ACC-04 як правило про сумку.
 "сумка":     dict(поле="ремінь_см", від="плече", правило="K-ACC-04",
                   чому="нижній край сумки на боці корпусу; його задає ДОВЖИНА РЕМЕНЯ, а не "
                        "габарит сумки — нижче лінії стегон ноги коротшають, НА лінії "
                        "стегон розширюється найширша точка"),
 "рукавички": dict(поле="край_руки_см", від="підлога",
                   чому="край рукавички на руці — лікоть, найширша точка біцепса; довжина "
                        "рукавички біжить обернено до довжини рукава, і обидва краї "
                        "оцінюються як ОДНЕ рішення (K-GLV-02), як взуття й поділ"),
}


def край_аксесуара(t, речі, вікно=None):
    """K-EDG-01 через K-FIT-03. Одна знахідка = один край, що сів на локальну опуклість
    там, де є куди його подіти.

    ДЕ ЛАМАЄТЬСЯ (тема-10 ЧАСТИНА I): правило дає ПОРЯДОК, не величину. Виміряні
    величини таких ефектів (тема-4 K-SIL-07) нижчі за нашу роздільність. Отже це
    впорядкування кандидатів, і НІКОЛИ не число, яке показують людині.

    K-SHO-07 (виріз читається лише на голій нозі) сюди НЕ входить: він не про край на
    тілі, а про те, чи край видно взагалі. Він живе у `видимість_краю`.
    """
    if not t or not t.get("профіль"):
        return []
    проф, зріст = t["профіль"], t["зріст"]
    зн = []
    for р in речі:
        сл = р.get("слот")
        сп = НОСІЇ_КРАЮ.get(сл)
        if not сп:
            continue
        назва = р.get("назва") or р.get("id") or "річ"
        край = _край_у_см(р, сп, t)
        if край is None:
            continue
        if not (0.0 <= край <= зріст):
            continue
        м = ПС.край_проти_локального(проф, край, вікно)
        if not (м["на_максимумі"] and м["важіль_є"]):
            continue
        лок = м["локальний_максимум"] or {}
        відрізки = ПС.вікно_краю(проф, край, вікно)
        сила_нп = round(min(1.0, (1.0 - (м["близькість"] or 0.0) / max(1e-6, 0.03)) * 0.5 + 0.5), 2)
        зн.append(dict(_зн("K-EDG-01", "soft",
            "край «%s» сів на опуклість (%s)" % (назва, лок.get("рівень", "?")),
            [назва],
            "%s; край на %.0f см, локальний максимум «%s» на %.0f см; вужче місце у вікні "
            "зсуву — %.0f см" % (сп["чому"], край, лок.get("рівень", "?"),
                                 лок.get("см", край), м["найвужче_см"]),
            ремонт=(["зсунути край у %s" % ", ".join("%.0f–%.0f см" % s for s in відрізки[:2])]
                    if відрізки else ["є куди зсунути край, але не в межах цієї моделі"]),
            ламається="правило дає ПОРЯДОК кандидатів, не величину: виміряні ефекти цього "
                      "класу нижчі за нашу роздільність, тому число людині не показується. "
                      "І «найширша точка литки» потребує ВИМІРУ литки — без нього профіль "
                      "спирається на популяційний шаблон, тобто на ярлик, який сам і забороняє",
            поріг=0.03, вимір=м["близькість"] or 0.0),
            сила_нп=сила_нп,
            сила_нп_джерело="вимір (fit.край_проти_локального: близькість до опуклості)"))
        _СЛ.запис("K-EDG-01", "край аксесуара на опуклості", "край_аксесуара",
                  значення="%s @ %.0f см" % (сл, край), сила=сила_нп,
                  напрям="той самий вимір, що K-FIT-03")
        if сп.get("правило"):
            _СЛ.запис(сп["правило"], "іменоване правило носія краю", "край_аксесуара",
                      значення="%s @ %.0f см" % (сл, край), сила=сила_нп,
                      напрям="K-EDG-01 — механізм; це — правило про цей обʼєкт")
    return зн


def _край_у_см(р, сп, t):
    """Величина речі → висота краю над підлогою. Кожен переклад названий."""
    знач = р.get(сп["поле"])
    if знач is None:
        return None
    знач = float(знач)
    зріст = t["зріст"]
    висоти = t.get("висоти") or {}
    if сп["від"] == "підлога":
        return знач
    if сп["від"] == "плече":
        # довжина ременя відкладається ВНИЗ від плеча: край сумки = плече − ремінь.
        # Це і є `strap drop` — те, що комерційне джерело назвало інженерною величиною
        # й що робить європейський крій 55–60 см правильним на 175 см і хибним на 158.
        плече = висоти.get("плечі")
        return None if плече is None else плече - знач
    return None


