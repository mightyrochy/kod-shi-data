# ЗВІДКИ ЧИСЛА, І ЧОМУ ВОНИ T3. Картка глибини вирізу в сантиметрах не називає
# ЖОДНОГО разу; єдине, що вона дає, — ТИП. Переклад типу в сантиметри падіння під
# основою шиї — конвенція, і вона МОЯ: жодне джерело корпусу глибин не міряло.
# Тому таблиця стоїть ОКРЕМИМ ІМЕНОВАНИМ РЯДКОМ із оголошеним походженням — той
# самий статус і той самий спосіб запису, що в температурної карти ніг вище
# («ПОБУДОВАНА з наявних входів, конвенція, некалібрована»), а не літералами,
# схованими в тілі функції. Умова перегляду теж та сама: перший фід, який назве
# глибину вирізу в сантиметрах, скасовує всю таблицю. Порядок між типами (стійка
# вище за круглий, круглий вище за квадратний, V найглибший) — не конвенція, а
# означення самих типів; некалібровані тут ВЕЛИЧИНИ кроку, не їхній порядок.
# ЧОМУ ПАДІННЯ, А НЕ ВИСОТА НАД ПІДЛОГОЮ: висота залежить від зросту, падіння —
# від крою. Ту саму різницю модуль уже тримає в `НОСІЇ_КРАЮ` полем `від`.
ГЛИБИНИ_ВИРІЗУ = {
 "стійка":      0.0,    # комір стоїть НА основі шиї: падіння нуль за означенням типу
 "хомут":       4.0,    # м'яка драпіровка трохи нижче основи шиї
 "човник":      4.0,    # човник ШИРОКИЙ, а не глибокий — це його означення
 "круглий":     7.0,
 "сорочковий":  9.0,
 "квадратний": 11.0,
 "V-подібний": 16.0,
}
ЛАНЦЮГОВІ_СЛОТИ = ("прикраси", "кольє", "намисто")


def _край_горловини(р, основа_шиї):
    """(висота краю горловини над підлогою, звідки взято) або (None, None).

    ДЖЕРЕЛО ПЕРЕД ЧИСЛОМ, як і всюди в модулі: виміряна довжина речі (`край_джерело
    == "річ"`) переважує конвенцію типу. Дефолт слота НЕ береться ніколи — саме він
    і зробив правило мертвим."""
    if р.get("край_джерело") == "річ" and р.get("верх_см") is not None:
        return float(р["верх_см"]), "вимір речі"
    г = ГЛИБИНИ_ВИРІЗУ.get(р.get("виріз_тип"))
    if г is None:
        return None, None
    return основа_шиї - г, "тип вирізу «%s», −%.0f см від основи шиї" % (р["виріз_тип"], г)


def кольє_проти_горловини(t, речі):
    """K-JEW-01. Кольє — це край, який НЕ МАЄ ЗБІГАТИСЯ з краєм горловини.

    ГЕНЕАЛОГІЯ ПЕРЕД ЗМІСТОМ (і вона обмежує силу, не зміст): сім ювелірних магазинів
    із однією таблицею довжин 14/16/18/20/24/28–36 дюймів — це ОДИН ГОЛОС, клас
    «анонімний комерційний контент». Жоден із них не показує рішення над конкретною
    людиною. Крізь фільтр проходить один механізм і одна відстань.

    ЩО ЦЕ МІНЯЄ (before/after). before — прикраси добираються за кольором і металом.
    after — вони добираються ще й за ПОЛОЖЕННЯМ ВЛАСНОГО КРАЮ відносно горловини речі,
    а горловину система вже знає (тип речі + зони). Це K-EDG-01 з іншим обʼєктом.

    ДЕ ЛАМАЄТЬСЯ: дюймові числа привʼязані до «середньої» шиї й «середнього» зросту —
    одне джерело визнає це саме й пропонує поправку ±1–2 дюйми на зріст. Тому правильна
    форма правила — НЕ ДОВЖИНА, а точка приземлення відносно ключиці й горловини, тобто
    знову вимір, а не ярлик.
    """
    if not t or not t.get("висоти"):
        return []
    основа_шиї = (t["висоти"].get("плечі"))
    if основа_шиї is None:
        return []
    прикраси = [р for р in речі if р.get("слот") in ЛАНЦЮГОВІ_СЛОТИ
                and р.get("ланцюг_см") is not None]
    верхи = [р for р in речі if р.get("слот") in ("верх", "сукня", "комплект")
             and _край_горловини(р, основа_шиї)[0] is not None]
    if not прикраси or not верхи:
        return []
    зн = []
    for п in прикраси:
        # ланцюг падає вдвічі меншою довжиною: замкнене коло довжиною L дає падіння L/2
        край_кольє = основа_шиї - float(п["ланцюг_см"]) / 2.0
        for в in верхи:
            край_горловини, звідки = _край_горловини(в, основа_шиї)
            зазор = abs(край_кольє - край_горловини)
            if зазор >= C["кольє_зазор_см"]:
                continue
            зн.append(dict(_зн("K-JEW-01", "soft",
                "кольє сідає на край горловини «%s» (зазор %.1f см)" % (звідки, зазор),
                [п.get("назва") or п.get("id"), в.get("назва") or в.get("id")],
                "кольє мусить сидіти ВИРАЗНО вище або виразно нижче краю горловини, ніколи "
                "на самому краї: на краї воно конкурує з тканиною замість обрамляти обличчя",
                ремонт=["коротший ланцюг — вище краю горловини",
                        "АБО довший — виразно нижче"],
                ламається="дюймові числа таблиць привʼязані до «середньої» шиї й «середнього» "
                          "зросту; одне джерело саме визнає це й дає поправку ±1–2 дюйми. "
                          "І генеалогія: сім магазинів з однією таблицею — один голос, клас "
                          "«анонімний комерційний контент», тому сила обмежена джерелом, а "
                          "не змістом. Крок 2 дюйми між шарами стека — з тієї ж лінії. "
                          "І другий бік: падіння горловини взято з ГЛИБИН_ВИРІЗУ — це "
                          "T3-конвенція під ТИПОМ вирізу, а не вимір речі; картка глибини "
                          "в сантиметрах не несе жодного разу",
                поріг=C["кольє_зазор_см"], вимір=зазор),
                сила_нп=round(min(0.8, (C["кольє_зазор_см"] - зазор) / C["кольє_зазор_см"] * 0.7 + 0.2), 2),
                сила_нп_джерело="вимір (|край кольє − край горловини|, см)"))
            _СЛ.запис("K-JEW-01", "кольє на краї горловини", "кольє_проти_горловини",
                      значення="%.1f см" % зазор, сила=0.5, напрям="K-EDG-01 з іншим обʼєктом")
    return зн
