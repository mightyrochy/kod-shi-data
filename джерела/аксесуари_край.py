#     Розвʼязання: де є ІМЕНОВАНЕ правило з власним джерелом — говорить воно;
#     K-EDG-01 лишається узагальненням для носіїв, які власного правила не мають.
#   · КОЛЬЄ. Механізм K-JEW-01 інший: край кольє порівнюється не з опуклістю ТІЛА, а
