"""СУД РЕЧІ НА ПОКУПКУ — та сама логіка, що й суд образу, на одній речі (наряд Функція-купити-річ, 12.11).

ЩО ЦЕ МІНЯЄ В РІШЕННІ. Доти окрема річ верху чи низу судилась лише кольором: крій проти фігури стояв рядком «судиться
в образі з другою половиною» (`річ_з_фото.вердикт`), а колір низу майже завжди «личить», бо далеко від обличчя (проба
12.11: п'ять спідниць — п'ять «невідомо» чи «кожна тобі пасує»). Тепер на одній речі судиться все, чому друга
половина образу не потрібна, — тими самими правилами, що в суді образу, без другого визначення:
  · край на її тілі — `fit.перевірити` (K-FIT-03: поділ проти рівнів і опуклостей її тіла, довжина виробу на її
    зрості; K-FIT-04: посадка пояса) і `суд_силует.карта_спідниць` (K-SIL-10: міді й максі на ЇЇ зрості);
  · крій проти фігури — `силует_суд.відповідність` (K-BOD-02 / K-SIL), як для сукні в `вердикт`;
  · роль кольору (K-COL-06 нейтраль чи колір; K-COL-02 гучний), з чим він складає схему (K-PAL-06 нейтраль +
    акцент) і куди світле, яскраве й блискуче веде погляд на її фігурі (K-COL-08, друга половина, тема-4:312).
Чого без другої половини судити не можна (чи верх сховає пояс, світлотна структура між речами), названо заявою.

РЕЧЕННЯ ПИШЕ МОВНА МОДЕЛЬ (аудит/ПРОДУКТ.md п.12): тут лише заяви кодами `внутрішня_мова.ЗАЯВИ`.

ВИБІР МІЖ РЕЧАМИ (`вибір`) — не правило стилю, а впорядкування вердиктів коду: рівень вердикту, тоді кількість
непройдених перевірок, тоді кількість не суджених; причина першої — заяви, якими вона відрізняється від решти. Рівних
код не розводить: «рівні — вибір за нею» (поза корпусом правил вибору не вигадує)."""
import fit as _ПС
import силует_пропорції as _СП
import silhouette as _S
import силует_суд as _СИЛ
import суд_силует as _ССЛ
import колір_річ as _КР
import palettes as _ПЛ
import реєстр_правил as _РП
import внутрішня_мова as _ВМ

# ── K-COL-08, ДРУГА ПОЛОВИНА: «Light / bright / shiny / warm advances and enlarges; dark / muted / matte / cool recedes»
# (тема-4_композиція-і-когерентність-EN.md:312). Межі — ті самі, що вже ділять нейтралі на ролі в продукті
# (`річ_з_фото.членство_в_палітрі`: темна нейтраль L* < 35, світла L* > 80), гучність — межа K-COL-02 `hi_C`, блиск —
# класи коду тканини 0–3 (2 — глянець, 3 — іскра; `річ_з_фото.ТЕКСТУРА_БЛИСК_ТКАНИНИ`, `каталог_розбір`). «Тепле
# / холодне» не судиться: межі тепла для речі в продукті нема — поза корпусом числа не вигадуємо.
ТЕМНА_L = 35.0
СВІТЛА_L = 80.0
БЛИСК_ВИСТУПАЄ = 2
# зона фігури, на яку річ слота кладе погляд (K-COL-08 — «куди веде погляд»; зони — тема-1 §2.1)
ЗОНА_СЛОТА = {"низ": "hips_legs", "верх": "bust_shoulders", "верхній_шар": "bust_shoulders",
              "сукня": "whole_figure", "комплект": "whole_figure"}
РІВНІ_ВЕРДИКТУ = ("личить", "з умовою", "невідомо", "краще інша")   # порядок вибору: перший — найкращий
# знахідки, що кажуть про РІЧ проти її тіла (K-BOD-05 — вісь тіла без вердикту, не про річ)
_НЕ_ПРО_РІЧ = ("K-BOD-05",)


def тіло_речі(річ_г, T, intent=_РП.ТИПОВИЙ_НАМІР):
    """Річ (геометрія `композитор_річ.у_річ`) проти її тіла → dict(знахідки, заяви, без_входу, судилось).

    `судилось` — чи хоч одна перевірка тіла дала вимір (край на її тілі чи знахідку): лише тоді «личить» має на
    чому стояти. Без тіла — заява, що саме назвати, і жодної знахідки."""
    слот = (річ_г or {}).get("слот")
    if not T or not T.get("профіль"):
        return dict(знахідки=[], заяви=[_ВМ.заява("figure_needs_measurements")],
                    без_входу=["фігура: зросту й обхватів нема — як річ сяде, не судиться"], судилось=False)
    знахідки, заяви, без_входу, судилось = [], [], [], False
    # ── край на її тілі: поділ із довжини виробу на її зрості, зі слова крамниці чи з фото ─────────────────
    клас = річ_г.get("довжина_клас_виміряний") if річ_г.get("край_джерело") == "виріб" else None
    if клас:
        заяви.append(_ВМ.заява("hem_on_her_body", level=клас, measured_from="garment_length"))
        судилось = True
    elif річ_г.get("край_джерело") in ("слово", "річ") and річ_г.get("довжина_рівень"):
        заяви.append(_ВМ.заява("hem_on_her_body", level=річ_г["довжина_рівень"], measured_from="shop_word"))
        судилось = True
    elif слот in ("низ", "сукня", "комплект", "верх", "верхній_шар"):
        заяви.append(_ВМ.заява("hem_not_judged", missing="garment_length"))
        без_входу.append("край: ні довжини виробу, ні слова довжини — де ляже поділ, не судиться")
    # ── K-FIT-03 / K-FIT-04 тим самим шаром посадки, що в суді образу ─────────────────────────────────────
    for з in _ПС.перевірити(T, [річ_г], intent=intent) or []:
        if з.get("правило") in _НЕ_ПРО_РІЧ:
            continue
        знахідки.append(з)
        заяви += [x for x in (з.get("заяви") or []) if isinstance(x, dict)]
    # ── K-SIL-10: міді й максі на її зрості ──────────────────────────────────────────────────────────────
    for з in _ССЛ.карта_спідниць([річ_г]):
        знахідки.append(з)
        заяви += [x for x in (з.get("заяви") or []) if isinstance(x, dict)]
    кр = річ_г.get("крій")
    if слот == "низ" and str(річ_г.get("тип") or "") == "спідниця" and _ССЛ.КАРТА_СПІДНИЦЬ.get(кр):
        заяви.append(_ВМ.заява("skirt_cut_reading", cut=кр,
                               reading={"free_text": _ССЛ.КАРТА_СПІДНИЦЬ[кр], "lang": "uk"}))
    # ── K-FIT-04: посадка низу — важіль лінії ніг; чи пояс видно, вирішує верх (друга половина) ─────────────
    if слот in ("низ", "комплект"):
        пос = річ_г.get("посадка")
        if пос:
            заяви.append(_ВМ.заява("rise_of_item", rise={"висока": "high", "середня": "mid",
                                                          "низька": "low"}.get(пос, _ВМ.UNKNOWN)))
        else:
            заяви.append(_ВМ.заява("rise_not_named"))
            без_входу.append("посадка: картка й фото її не називають — важіль K-FIT-04 не судиться")
    # ── K-BOD-02 / K-SIL: крій проти фігури — той самий суддя, що для сукні у `вердикт` ─────────────────────
    зс = _СИЛ.відповідність(T, _S.обгортка(T, [річ_г]), intent) if кр else []
    if зс:
        знахідки += зс
        судилось = True
        for з in зс:
            заяви += [x for x in (з.get("заяви") or []) if isinstance(x, dict)]
    elif not кр:
        заяви.append(_ВМ.заява("cut_vs_figure_not_judged", missing="cut"))
    elif _СП.бік_пари(T).get("бік") is None:
        # бік пари плечі/стегна не доведено понад похибку самовиміру (`силует_пропорції.бік_пари`): у реєстрі
        # похибок обхват плечей без джерела (`похибка_вимірів_тіла.РЕЄСТР`), тож ширшу половину код не називає
        заяви.append(_ВМ.заява("cut_vs_figure_not_judged", missing="measurement_error"))
        без_входу.append("крій проти фігури: ширша половина фігури не доведена понад похибку самовиміру")
    return dict(знахідки=знахідки, заяви=заяви, без_входу=без_входу, судилось=судилось)


def колір_речі(колір, слот, блиск=None, палітра=None):
    """Роль кольору речі, з чим він складає схему, і куди річ веде погляд → список заяв.

    `колір` — свідок кольору речі у формі запису каталогу (`lab`/`hex`, `колір_тип`, `колір_не_вимір` з вікном слова):
    вимір — точка, слово крамниці — вікно. Роль — `колір_річ.нейтраль_меж` (K-COL-06), та сама, що в суді образу: вікно
    слова дає роль, лише коли всі його точки на одному боці. `палітра` — `palettes.палітра_практична` її кольорів або
    None (кольорів не прочитано: партнерів названо роллю, а не кольорами). Кольору не виміряно й слово його не
    обмежує — роль не суджено (`colour_role_not_judged`), а блиск веде погляд і без кольору (K-COL-08)."""
    м = _КР.межі_кольору(колір) if isinstance(колір, dict) else None
    роль = _КР.нейтраль_меж(колір) if м is not None else None
    зона = ЗОНА_СЛОТА.get(слот)
    if роль not in ("так", "ні"):
        блискуча = блиск is not None and блиск >= БЛИСК_ВИСТУПАЄ
        return [_ВМ.заява("colour_role_not_judged", missing="colour_measure")] + (
            [_ВМ.заява("draws_eye_enlarges", zone=зона, by=["shiny"])] if зона and блискуча else [])
    L0, L1, C0, _C1, _д = м
    нейтраль = роль == "так"
    гучний = (not нейтраль) and C0 >= _РП.C["hi_C"]
    заяви = []
    # K-COL-06: нейтраль — основа образу, колір — акцент (K-COL-02: гучний — уся зона кольору понад поріг)
    заяви.append(_ВМ.заява("colour_role_base") if нейтраль else _ВМ.заява("colour_role_accent", loud=bool(гучний)))
    # K-PAL-06: нейтраль + акцент — партнер протилежної ролі з ЇЇ палітри
    if палітра and палітра.get("кольори"):
        партнери = [к for к in палітра["кольори"] if (к.get("роль") == "колір") == нейтраль]
        коди = [к.get("назва") or к.get("hex") for к in партнери[:3] if к.get("назва") or к.get("hex")]
        if коди:
            заяви.append(_ВМ.заява("pairs_with_colours", colours=коди, scheme="neutral_plus_accent"))
    else:
        заяви.append(_ВМ.заява("pairs_with_role_palette_unknown", partner="accent" if нейтраль else "neutrals"))
    # K-COL-08: світле, яскраве, блискуче виступає й збільшує; темне, приглушене, матове відступає (тема-4:312);
    # для вікна слова — лише коли так каже вся його зона світлоти
    чим = [x for x, так in (("light", L0 > СВІТЛА_L), ("bright", гучний),
                             ("shiny", блиск is not None and блиск >= БЛИСК_ВИСТУПАЄ)) if так]
    if зона and чим:
        заяви.append(_ВМ.заява("draws_eye_enlarges", zone=зона, by=чим))
    elif зона and L1 < ТЕМНА_L and not гучний and not (блиск or 0) >= 1:
        заяви.append(_ВМ.заява("recedes_zone", zone=зона))
    return заяви


def вибір(вердикти):
    """{ід: вердикт} речей, між якими вона вибирає, → dict(порядок, заяви).

    Порядок — за рівнем вердикту (`РІВНІ_ВЕРДИКТУ`), тоді менше непройдених перевірок, тоді менше не суджених.
    Перша дістає заяву `buy_first` з кодами заяв, яких у решти нема (чим вона відрізняється); рівні за всіма трьома —
    `buy_order_tie`. Менше двох речей — вибору нема."""
    ід = [і for і, в in (вердикти or {}).items() if isinstance(в, dict)]
    if len(ід) < 2:
        return dict(порядок=ід, заяви=[])

    def ключ(і):
        в = вердикти[і]
        чл = в.get("чекліст") or {}
        р = в.get("рівень")
        return (РІВНІ_ВЕРДИКТУ.index(р) if р in РІВНІ_ВЕРДИКТУ else len(РІВНІ_ВЕРДИКТУ),
                len(чл.get("провал") or ()), len(чл.get("без_входу") or ()))
    порядок = sorted(ід, key=ключ)
    if ключ(порядок[0]) == ключ(порядок[1]):
        return dict(порядок=порядок, заяви=[_ВМ.заява("buy_order_tie", item_ids=порядок)])

    def коди(і):
        пов = (вердикти[і].get("повідомлення") or {}).get("statements") or []
        return {з.get("code") for з in пов if isinstance(з, dict)}
    інші = set().union(*(коди(і) for і in порядок[1:]))
    свої = sorted(коди(порядок[0]) - інші)
    return dict(порядок=порядок, заяви=[_ВМ.заява("buy_first", item_ids=[порядок[0]], reasons=свої,
                                                  then=порядок[1:])])
