def блиск_бюджет(E, intent="conventional", нагода=None):
    """K-MAT-04 (+K-KOH-06, шкала R-TEX-02) — усе з ВЛАСНОГО корпусу; веб дав лише
    незалежне підтвердження («одна головна іскра» — 8 джерел 2023–26) і ОДНУ механіку,
    якої в корпусі немає: СУСІДСТВО.

    Три знахідки, і вони про різне:
      K-MAT-04   — кількість поверхонь вираженого блиску (≥2 за шкалою) понад бюджет.
                   Бюджет 2, вечір/формальна нагода +1 (K-KOH-06).
      K-MAT-04-L — м'який люстр (рівень 1) — фонова властивість, бюджету не витрачає,
                   але такий фон ОДИН: два люстрові фони вже читаються як «все блищить».
      K-MAT-04-A — НОВЕ, не з корпусу: два блискучі поруч по тілу підсилюють одне одного;
                   те саме через матову річ між ними — не проблема. Джерело — ремесло
                   («два блискучі відштовхуються; паєткові штани + блискуче намисто
                   нормально, бо між ними матовий верх»), тому це T3-кандидат, і сила
                   свідомо нижча за бюджетну знахідку.

    Числа T3. Блиск НЕ вимірюється з фото — приходить полем речі (VLM або каталог)."""
    # блиск — властивість МАТЕРІАЛУ речі, не окремого кольору: рахуємо по речах
    з_блиском = [e for e in одна_на_річ(E) if (e.get("блиск") or 0) >= 1]
    if not з_блиском:
        return []
    вечір = (нагода in ("формал_вечір", "вечір", "свято", "весілля_гість")
             or intent in ("statement", "editorial"))
    бюджет = БЛИСК_БЮДЖЕТ + (БЛИСК_ВЕЧІР if вечір else 0)
    виражені = [e for e in з_блиском if (e.get("блиск") or 0) >= 2]
    люстри = [e for e in з_блиском if (e.get("блиск") or 0) == 1]
    зн = []
    if len(виражені) > бюджет:
        над = len(виражені) - бюджет
        сила_нп = round(min(1.0, над / 2.0), 2)          # T3: +2 поверхні -> повна сила
        зн.append(dict(_зн("K-MAT-04", "soft" if сила_нп >= C["нп_межа_soft"] else "hint",
            "поверхонь вираженого блиску більше за бюджет", [e["річ"] for e in виражені],
            "%d поверхон(ь) блиску ≥2 при бюджеті %d%s" % (
                len(виражені), бюджет, " (вечір/нагода дали +1)" if вечір else ""),
            ремонт=["лишити ОДНУ головну іскру, решту взяти в матовому чи брашованому фініші",
                    "АБО прибрати блиск з найбільшої площі — вона й так тримає увагу"],
            ламається="дзеркальний рівень 3 майже завжди стає фокусом сам собою: тоді це не "
                      "перевитрата бюджету, а один свідомий фокус — залежить від наміру",
            поріг=float(бюджет), вимір=float(len(виражені))),
            сила_нп=сила_нп, сила_нп_джерело="вимір (власний: перевитрата бюджету)"))
    if len(люстри) > 1:
        сила_нп = round(min(1.0, (len(люстри) - 1) / 2.0) * 0.5, 2)   # T3, свідомо слабше
        зн.append(dict(_зн("K-MAT-04-L", "hint",
            "кілька люстрових фонів — фон перестає бути фоном", [e["річ"] for e in люстри],
            "%d поверхонь м'якого люстру; за R-TEX-02 такий фон один на образ" % len(люстри),
            ремонт="лишити один люстровий фон, решту в матовому",
            ламається="люстр бюджету не витрачає — це саме про ФОН, а не про іскру",
            поріг=1.0, вимір=float(len(люстри))),
            сила_нп=сила_нп, сила_нп_джерело="вимір (власний: кількість люстрових фонів)"))
    for i, a in enumerate(виражені):
        for b in виражені[i+1:]:
            ia = ПОРЯДОК_ТІЛА.get(a["слот"]); ib = ПОРЯДОК_ТІЛА.get(b["слот"])
            if ia is None or ib is None: continue
            d = abs(ia - ib)
            if d > 1: continue
            між = [e for e in одна_на_річ(E) if ПОРЯДОК_ТІЛА.get(e["слот"]) is not None
                   and min(ia, ib) <= ПОРЯДОК_ТІЛА[e["слот"]] <= max(ia, ib)
                   and (e.get("блиск") or 0) == 0]
            if між: continue                    # матова річ між ними — розводить
            сила_нп = round(0.5 * (1.0 if d == 0 else 0.7), 2)      # T3
            зн.append(dict(_зн("K-MAT-04-A", "hint",
                "два блискучі поруч по тілу — підсилюють одне одного",
                [a["річ"], b["річ"]],
                "слоти «%s» і «%s» сусідні (відстань %d), матової речі між ними немає"
                % (a["слот"], b["слот"], d),
                ремонт=["рознести: лишити блиск в одній зоні, а сусідню взяти матовою",
                        "АБО поставити матову річ між ними"],
                ламається="механіка з ремесла, не з корпусу й не вимір — T3-кандидат; "
                          "на дрібних площах (сережки+намисто) ефект може бути бажаним"),
                сила_нп=сила_нп, сила_нп_джерело="категорія (сусідство, не градієнт)"))
    return зн
МЕТАЛИ_ТЕПЛІ = ("золото", "бронза", "латунь", "мідь")
МЕТАЛИ_ХОЛОДНІ = ("срібло", "біле_золото", "платина", "сталь")
МЕТАЛИ_МІСТ = ("рожеве_золото",)          # проміжний за ТЕМПЕРАТУРОЮ (не теплий, не холодний)
КОНЕКТОРИ = ("двотонний", "два_тони")     # ЛЕГІТИМІЗУЄ мікс — тільки двотонна річ
# ВИПРАВЛЕНО (баг): раніше обидві категорії були одним списком, і самотнє рожеве золото
# серед срібла давало НУЛЬ знахідок — воно «вважалося конектором». Джерела називають
# конектором саме двотонну річ («a piece that contains both metals»), а рожеве золото —
# третій металевий тон, який сам потребує повтору.


def метали(E, F, source="uncontrolled", драп=None, intent="conventional", речі=None, прикраси=None):
    """Вплив металів. ДВА правила, і вони про різне:

    `прикраси` (рядок 108, 20.09.2026) — її бажання про метал прикрас З ЦИМ образом
    («золото» | «срібло» | «інші» | «без прикрас»). Воно ПЕРЕВАЖАЄ драпіровку профілю
    в K-COL-06-M: провідний метал звіряється з бажанням, а не з «що до лиця»; коли
    бажання суперечить драпіровці — знахідка каже це hint-регістром і не забороняє
    (R-TYP-04: її рішення про сьогодні, не помилка). Без бажання — як доти.

    K-CRA-07 «мікс без повтору» — з ВЛАСНОГО корпусу: K-COMP-03 прямо каже «метали —
    теж акценти: узгодити або міксувати з ПОВТОРОМ», а «мікс металів без повтору» стоїть
    у списку фейлів. Ювелірне ремесло (9 незалежних джерел 2025–26) сходиться на тій самій
    механіці: метал, що з'явився РАЗ серед іншого металу, читається як випадковість, двічі —
    як вибір. Це не нова механіка: та сама логіка, що K-COL-05 (акцент-сирота проти ехо),
    лише ознака інша — не колірна сім'я, а метал. Тому сила рахується так само: наскільки
    самотній елемент і наскільки він близько до обличчя.

    K-COL-06-M «ведучий метал». ТІР УТОЧНЕНО ФІЗИКОЮ (не блогами): напрям оптичного
    ефекту — ВИМІРЯНИЙ. Золото відбиває довгохвильову частину спектра і майже не
    відбиває синьо-фіолетову: ~84% на 700 нм проти ~25% на 400 нм, різниця ~3.4× (причина —
    релятивістські ефекти в зовнішніх орбіталях; Pyykkö & Desclaux), домінантна довжина
    ≈576 нм. Срібло має високу відбивність по ВСЬОМУ видимому діапазону, тому безбарвне
    (Engineering LibreTexts). Разом із R-CHEV-06 (індукція біля обличчя — перцептивна
    фізика) це дає механізм: золото біля обличчя підмішує в шкіру тепле світло, срібло
    підіймає світлоту майже без зсуву тону. Отже НАПРЯМ ефекту — T1/T2, а от ЩО з цього
    «лестить» лишається конвенцією (R-CHEV-12/R-PC-06 T4) і вирішується метою людини.
    ПОБІЧНИЙ НАСЛІДОК, який варто перевірити: якщо срібло біля обличчя піднімає світлоту
    без зсуву тону, воно працює у вісь K-CLR-02 (приобличчевий контраст), а не в цю —
    зараз цього зв'язку в коді немає. Тут ДИСЦИПЛІНА R-PC-04 має практичний наслідок: якщо людина
    САМА сказала на елісітації «мені золото», правило НЕ сперечається з нею на підставі
    фото. Воно говорить лише коли (а) елісітації не було — тоді слабко, зі стелею фото,
    або (б) провідний метал образу суперечить тому, що людина назвала.
    K-CLR-05 (олива → «метали часто обидва») гасить це правило на оливковому підтоні.

    Ослаблення міксу: двотонна річ-конектор (4 джерела називають її легітимізатором) —
    коли вона в образі, вимога повтору майже знімається. Полірування теж модулює:
    висока полірованість підсилює контраст металів, мішані фініші згладжують."""
    метал_е = [e for e in E if e.get("метал")]
    if not метал_е:
        return []
    def клас(м):
        if м in МЕТАЛИ_ТЕПЛІ: return "теплий"
        if м in МЕТАЛИ_ХОЛОДНІ: return "холодний"
        return "міст"          # рожеве золото й двотонні — проміжні за температурою
    групи = {}
    for e in метал_е:
        групи.setdefault(e["метал"], []).append(e)
    конектор = any(e["метал"] in КОНЕКТОРИ for e in метал_е)
    зн = []

    # ── K-CRA-07: мікс без повтору ────────────────────────────────────────────
    справжні = {м: g for м, g in групи.items() if м not in КОНЕКТОРИ}
    if len(справжні) >= 2:
        for м, g in справжні.items():
            if len(g) != 1:
                continue
            інших = sum(len(x) for мм, x in справжні.items() if мм != м)
            near = max((e.get("near") or 0.2) for e in g)
            база = min(1.0, інших / 3.0)          # T3: 1 інша річ -> 0.33, 3+ -> 1.0
            # ФІНІШ модулює: полірований метал підсилює контраст, брашований/оксидований
            # згладжує («highly polished metals emphasize contrast; mixing finishes softens it»).
            фін = max([ФІНІШ_ФАКТОР.get(e.get("полірування"), 1.0) for e in g] or [1.0])
            сила_нп = round(min(1.0, база * max(0.25, near) * фін
                                 * (0.25 if конектор else 1.0)), 2)
            зн.append(dict(_зн("K-CRA-07", "soft" if сила_нп >= C["нп_межа_soft"] else "hint",
                "метал з'являється один раз — читається як випадковість, не вибір",
                [e["річ"] for e in g],
                "«%s» один проти %d реч(ей) іншого металу; приобличчева вага %.2f%s"
                % (м, інших, near, "; у образі є двотонна річ-конектор" if конектор else ""),
                ремонт=["повторити «%s» ще раз у другій зоні (вуха↔зап'ясток↔пальці) — "
                        "два входження читаються як намір" % м,
                        "АБО прибрати цю річ і лишити один метал",
                        "АБО додати двотонну річ-конектор, яка легітимізує мікс"],
                ламається="ремесло ювелірне, не вимір: «раз=випадковість» перевіряється лише "
                          "людським прочитанням; на дрібних речах далеко від обличчя ефект "
                          "слабкий, тому сила вже помножена на приобличчеву вагу",
                поріг=2.0, вимір=float(len(g))),
                сила_нп=сила_нп,
                сила_нп_джерело="вимір (власний: самотність × приобличчева вага)"))

    # ── K-CRA-07-N: скільки МЕТАЛЕВИХ ТОНІВ узагалі ────────────────────────────
    # Ремесло: «тримайся двох-трьох тонів, більше читається як шум». Це інша величина, ніж
    # повтор: там питання «чи кожен тон повторений», тут «чи тонів не зазбагато».
    if len(справжні) > 2:
        сила_нп = round(min(1.0, (len(справжні) - 2) / 2.0), 2)     # T3: 4 тони -> 1.0
        зн.append(dict(_зн("K-CRA-07-N", "hint",
            "металевих тонів більше за два — мікс перестає читатись як задум",
            [e["річ"] for g in справжні.values() for e in g],
            "тонів %d: %s" % (len(справжні), ", ".join(sorted(справжні))),
            ремонт=["звести до двох тонів, третій прибрати або замінити на двотонну річ",
                    "АБО лишити третій лише в одній дрібній речі далеко від обличчя"],
            ламається="ремесло, не вимір; на дрібних різнорідних речах (вінтажний стек) "
                      "багато тонів може бути свідомим ходом",
            поріг=2.0, вимір=float(len(справжні))),
            сила_нп=сила_нп, сила_нп_джерело="вимір (власний: кількість металевих тонів)"))

    # ── K-COL-06-M: ведучий метал проти температури особи ───────────────────────
    ведучий = max(метал_е, key=lambda e: (e.get("near") or 0.0, e.get("площа") or 0.0))
    к_вед = клас(ведучий["метал"])
    названий = (драп or {}).get("метал") if isinstance(драп, dict) else None
    олива = any(str(f.get("undertone", "")).startswith("олив")
                for k, f in F.items() if not k.startswith("_") and isinstance(f, dict))
    # ── БАЖАННЯ З ЦИМ ОБРАЗОМ ПЕРЕВАЖАЄ ДРАПІРОВКУ (рядок 108) ──────────────
    _баж = str(прикраси or "").strip().lower()
    _клас_баж = {"золото": "теплий", "срібло": "холодний"}.get(_баж)
    if _баж in ("золото", "срібло", "інші", "без прикрас"):
        _near = max(0.25, ведучий.get("near") or 0.2)
        if _баж == "без прикрас":
            зн.append(dict(_зн("K-COL-06-M", "hint",
                "вона просила образ без прикрас — а прикраса в образі є",
                [e["річ"] for e in метал_е],
                "«%s» у слоті %s; слово її: «без прикрас»" % (ведучий["метал"], ведучий.get("слот")),
                ремонт=["прибрати прикраси — це її рішення про сьогодні, не помилка коду"],
                ламається="це не вердикт про метал: підстава — її слово, і коли вона передумала, "
                          "правило втрачає ґрунт"),
                сила_нп=round(0.6 * _near, 2), сила_нп_джерело="вимір (власний: приобличчева вага)"))
        elif _баж == "інші":
            зн.append(dict(_зн("K-COL-06-M", "hint",
                "вона хотіла інші прикраси (перли, дерево, без металу) — веде металева",
                [ведучий["річ"]],
                "веде «%s»; її слово: «інші» — фід метал перлів/дерева не називає, тож це лише натяк"
                % ведучий["метал"],
                ремонт=["поставити біля обличчя річ без металевого блиску, метал — далі"],
                ламається="слово «інші» фід не вміє звірити: перли й дерево йдуть без поля металу"),
                сила_нп=round(0.3 * _near, 2), сила_нп_джерело="вимір (власний: приобличчева вага)"))
        elif к_вед != "міст" and _клас_баж and к_вед != _клас_баж:
            сила_нп = round(0.6 * _near, 2)
            зн.append(dict(_зн("K-COL-06-M", "soft" if сила_нп >= C["нп_межа_soft"] else "hint",
                "провідний метал образу — не той, що вона хоче з цим образом",
                [ведучий["річ"]],
                "веде «%s» (%s), а з цим образом вона хоче «%s»" % (ведучий["метал"], к_вед, _баж),
                ремонт=["поставити «%s» біля обличчя, а «%s» лишити далі або прибрати" % (_баж, ведучий["метал"])],
                ламається="це НЕ вердикт про підтон: підстава — її слово про сьогодні (R-TYP-04)"),
                сила_нп=сила_нп, сила_нп_джерело="вимір (власний: приобличчева вага)"))
        # бажання проти драпіровки профілю — сказати, не заборонити (R-TYP-04, без вироку)
        if _клас_баж and названий and клас(названий) not in ("міст", _клас_баж) and к_вед == _клас_баж:
            зн.append(dict(_зн("K-COL-06-M", "hint",
                "з цим образом вона хоче метал не той, що назвала своїм до лиця — її рішення, не помилка",
                [ведучий["річ"]],
                "сьогодні «%s», у профілі (драпіровка) «%s»; образ веде «%s» — за її словом про сьогодні"
                % (_баж, названий, ведучий["метал"]),
                ремонт=["нічого: рішення про цей вихід — її; якщо хоче звірити з тим, що до лиця, — "
                        "спробувати «%s» біля обличчя" % названий],
                ламається="обидва входи — її слова; правило лише називає розходження й не обирає за неї"),
                сила_нп=round(0.2 * _near, 2), сила_нп_джерело="вимір (власний: приобличчева вага)"))
    elif к_вед != "міст":
        if названий:
            # людина сама назвала метал: сперечатися з нею фото не будемо
            к_наз = клас(названий)
            if к_наз != "міст" and к_наз != к_вед:
                сила_нп = round(0.6 * max(0.25, ведучий.get("near") or 0.2), 2)
                зн.append(dict(_зн("K-COL-06-M", "soft" if сила_нп >= C["нп_межа_soft"] else "hint",
                    "провідний метал образу — не той, що людина назвала своїм",
                    [ведучий["річ"]],
                    "веде «%s» (%s), а на елісітації названо «%s» (%s)"
                    % (ведучий["метал"], к_вед, названий, к_наз),
                    ремонт=["поставити «%s» біля обличчя, а «%s» лишити далі" % (названий, ведучий["метал"]),
                            "АБО свідомо йти проти — це законний хід, просто не за замовчуванням"],
                    ламається="це НЕ вердикт про підтон: підстава тут — власна відповідь людини, "
                              "а не фото; якщо вона змінила думку, правило втрачає ґрунт"),
                    сила_нп=сила_нп, сила_нп_джерело="вимір (власний: приобличчева вага)"))
        else:
            try:
                import palette as _P
                # Ті самі два входи, що й у температура_нейтралі (Н-palette-2-101):
                # тут ведуча річ відома як ведучий["річ"]. Знак і впевненість, які
                # це правило читає, від множників не залежать — вони рухають лише
                # `вага_вікна`; передаємо їх, щоб `нейтраль_якір` в обох живих
                # викликах бачив ОДИН і той самий вхід, а не два різні.
                _річ_в = next((r for r in (речі or []) if isinstance(r, dict)
                               and r.get("id") == ведучий["річ"]), None)
                _к_в, _ = _P.контакт_із_речі(_річ_в or {})
                # ДРАП ІДЕ ДАЛІ (Н-V04-013, крок 3). Функція драп уже приймала
                # і просто не віддавала — доти це було невидно, бо фото давало
                # знак у будь-якому разі. Відколи непідтверджений знак гасне
                # (`нейтраль_якір`, гейт `вісь_знак_придатний`), ця гілка без
                # драпу дала б w=0, і правило металу мовчало б там, де людина
                # відповідь ДАЛА — лише не словом «метал», а білим чи нейтралями.
                як = _P.нейтраль_якір(F, source=source, слот=ведучий["слот"],
                                      intent=intent, near=ведучий.get("near"),
                                      драп=драп,
                                      хрома_речі=lch(ведучий["lab"])[1],
                                      контакт=_к_в)
                w = як.get("тепло_особи") or 0.0
                впев = як.get("впевненість") or 0.0
            except Exception as _e:
                import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
                if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
                w, впев = 0.0, 0.0
            проти = (w > 0 and к_вед == "холодний") or (w < 0 and к_вед == "теплий")
            # ── ПІДЛОГА МІРЯЄТЬСЯ ДО ОКРУГЛЕННЯ, А НЕ ПІСЛЯ (17.09.2026) ─────
            # ЩО ЦЕ МІНЯЄ В РІШЕННІ. Вікно, у якому K-CLR-05 узагалі має що
            # сказати, вузьке за побудовою: незагашена сила мусить бути НЕ нижче
            # підлоги (0.05), а загашена вчетверо — нижче. Тобто сира сила має
            # лягти в [0.05, 0.125). Обидва числа округлювались до сотих ДО
            # порівняння, і на цьому вікно зникало: 0.1225 × 0.4 = 0.049 — нижче
            # підлоги, — але round(0.049, 2) = 0.05, тобто РІВНО підлога, і
            # `_під_підлогою` (строге «<») відповідав False.
            # ВИМІРЯНО на `каталог_повний.xml` і людині стенда (оливковий підтон,
            # 43 речі з металом × 7 варіантів елісітації = 301 прогін): досяжні
            # значення сирої сили — 0.0, 0.12, 0.14, 0.17, 0.30, 0.32, 0.35, 0.38.
            # Єдине, що лягає у вікно, — 0.12, і саме воно після подвійного
            # округлення давало рівно 0.05. Правило було зелене в усіх тестах (там
            # числа пишуть рукою) і мовчало на реальних даних назавжди — той самий
            # клас дефекту, що вже спійманий у `ВОЛОГА_ВІДМОВА` (домовились про
            # поле, не домовились про форму значення).
            # ОКРУГЛЕННЯ ЛИШАЄТЬСЯ ТАМ, ДЕ ЙОМУ МІСЦЕ: у тому, що ЧИТАЮТЬ (суть,
            # `сила_нп` знахідки). Порівнюються сирі.
            _сира_без = abs(w) * впев * max(0.25, ведучий.get("near") or 0.2)
            _сира_нп = _сира_без * (0.4 if олива else 1.0)
            _сила_без = round(_сира_без, 2)
            сила_нп = round(_сира_нп, 2)
            # ── K-CLR-05 ГАСИВ ПРАВИЛО МЕТАЛУ Й ЗНИКАВ РАЗОМ ІЗ НИМ ──────────
            # ЗНАЙДЕНО ПРОГОНОМ ГІЛОК (батарея gate_reach): K-CLR-05 реалізований
            # як МНОЖНИК 0.4 усередині гілки, яку потім відсікає підлога сили.
            # На теплій оливковій шкірі зі сріблом біля обличчя це давало рівно
            # те, чого правило й хоче — мовчання, — але мовчання БЕЗ ПРИЧИНИ:
            # знахідки нема, отже нема й згадки, що метал узагалі розглядався.
            # Стиліст не міг відрізнити «правило перевірено й утримано на
            # оливковому підтоні» від «правило не спрацювало».
            #
            # ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after):
            #   before — на такому образі про срібло не сказано нічого. Питання
            #            «а метал тут доречний?» лишається відкритим і, найімовірніше,
            #            буде поставлене вдруге — уже людиною.
            #   after  — сказано: правило металу перевірене й УТРИМАНЕ, бо підтон
            #            оливковий і на ньому обидва метали ходять. Питання закрите.
            # Це не нове твердження про річ: сила лишається нульовою, гейтом воно
            # не стає. Змінюється тільки те, чи видно ухвалене рішення.
            якщо_загасило = (проти and олива and not _під_підлогою(_сира_без)
                             and _під_підлогою(_сира_нп))
            if якщо_загасило:
                зн.append(dict(_зн("K-CLR-05", "утримано",
                    "правило провідного металу утримано: підтон оливковий",
                    [ведучий["річ"]],
                    "веде «%s» (%s) проти тепла особи %+.2f — без оливкового підтону "
                    "це дало б силу %.2f. K-CLR-05: на оливковому підтоні метали "
                    "часто працюють обидва, тому вимір гаситься до %.2f, нижче "
                    "підлоги %.2f, і правило нічого не стверджує"
                    % (ведучий["метал"], к_вед, w, _сила_без, сила_нп, _підлога_нп()),
                    ремонт=["нічого: це утримання, а не знахідка. Якщо метал важливий — "
                            "спитати людину напряму (елісітація первинна за R-PC-04)"],
                    ламається="сам множник 0.4 — конвенція, не вимір: корпус каже "
                              "НАПРЯМ («часто обидва»), не величину гасіння"),
                    сила_нп=None,
                    сила_нп_джерело="виміру нема (утримано): K-CLR-05 загасив вимір "
                                    "нижче підлоги"))
            if проти and not _під_підлогою(_сира_нп):
                зн.append(dict(_зн("K-COL-06-M", "hint",
                    "провідний метал проти температури особи (з фото, не з елісітації)",
                    [ведучий["річ"]],
                    "веде «%s» (%s), тепло особи %+.2f, впевненість входу %.2f%s"
                    % (ведучий["метал"], к_вед, w, впев,
                       "; підтон оливковий — K-CLR-05: метали часто обидва, тому гасимо" if олива else ""),
                    ремонт=["спитати людину напряму: золото чи срібло виграшніше біля обличчя "
                            "(елісітація — первинне джерело за R-PC-04, фото лише assist)",
                            "АБО перенести цей метал далі від обличчя"],
                    ламається="warm-cool таксономія металів — конвенція (R-CHEV-12/R-PC-06 T4), "
                              "не механізм; сила вже обмежена стелею фото й приобличчевою вагою"),
                    сила_нп=сила_нп, сила_нп_джерело="вимір (власний: |тепло|×впевненість×near)"))
    return зн
