def _схему_обрала_вона(сценарій):
    """Чи ЖІНКА поставила межу, яку тримає K-PAL-03 — чи її поставив хтось за неї.

    Н-1 (рішення власника «13А»). `вибір_палітри.для_суду` (П-7) уже везе
    в сценарій, хто обрав схему: `her` — вона сама на екрані палітри; `stylist` — вона
    лишила вибір стилістці, і схему обрала МОДЕЛЬ з причиною; `code_rank` — не
    обирав ніхто, схему взяв перший ранг коду. Межа людини є рівно в першому випадку.
    Поля в сценарії нема (CLI, батареї, стенд без екрана палітри) — не питали, і
    поведінка лишається як доти: `None`, гейт як був."""
    вс = (сценарій or {}).get("вибір_схеми")
    хто = ((вс or {}).get("обрала") or {}).get("scheme") if isinstance(вс, dict) else None
    return None if хто is None else (хто in ("her", "conversation"))

def схема_образу(речі, спец_слоти, за_ід=None, сценарій=None):
    """[знахідки] K-PAL-03 — річ поза дугою обраної схеми, або кольорова річ на
    нейтральній ролі. Дуга схеми — межа, яку обрала жінка, а не порада:
    доти червона сумка в «тональній сливовій» не давала жодної знахідки.

    …А КОЛИ ОБРАЛА НЕ ЖІНКА, ЦЕ НЕ МЕЖА (Н-1, рішення власника «13А»).
    Відколи схему, яку вона лишила стилістці, обирає модель, той самий гейт
    зупиняв образ за припис, якого жінка не давала, — і образ ішов у добір кодом
    замість того, щоб доїхати до картки. Тепер: схему обрала ВОНА — гейт, як був;
    обрала модель або взяв ранг коду — та сама знахідка СЛАБШИМ регістром («репліка»,
    сила `strong` замість `hard`) з названим полем `чия_схема`, і образ їде на картку
    з м'якою приміткою. Звіт Research про композицію каже те саме з іншого боку:
    схожість тону — бал, контраст — законний прийом, шаблони Matsuda сприйняття не
    доводять (клас C), тож гейта поза межею людини під цим правилом нема на чому
    тримати."""
    if not спец_слоти or not isinstance(спец_слоти, dict):
        return []
    # ТРАУРНА НАГОДА, СХЕМУ ВЗЯВ КОД: її дуги тут не межа — межу ставить
    # траурний регістр пулу. Виміряно на похороні (сід 3, 10 образів): без цього рядка
    # K-PAL-03 гейтом блокував 2 образи за темно-синю й бордову речі поза бірюзовою
    # дугою «тональної», якої жінка не обирала. Схему, обрану нею, судить як доти.
    if спец_слоти.get("_траур"):
        return []
    # Н-1: `межа_людини` — факт ЦЬОГО прогону (хто обрав схему), не друга політика. Силу,
    # регістр, вагу, `блокує` і слово репліки дає конструктор (Е3-сила-правила, п.1а): доти
    # знахідка будувалась словником, а регістр рахувався тут, повз стелі тіру й корпусу.
    _вона = _схему_обрала_вона(сценарій)
    _сила = "hard" if _вона is not False else "strong"
    _чия = None if _вона is not False else (
        ((сценарій or {}).get("вибір_схеми") or {}).get("обрала", {}).get("scheme"))
    _мʼяко = (dict(чия_схема=_чия,
                   примітка="схему обрала не жінка, а %s — дуга тут не межа людини, "
                            "а вибір за неї: образ іде на картку з приміткою, не в ремонт"
                            % ("стилістка (модель, #411)" if _чия == "stylist" else "ранг коду"))
              if _чия else {})

    def _межа(ід, с, суть, чому, ярлик, що_зняло_б, **решта):
        """Знахідка K-PAL-03 межі схеми: конструктор із фактом межі людини й поля суду.

        `решта` — `заяви`, `ремонт_заяви` конструктора; та сама форма, що `_дод` прийомів палітри:
        поля однієї знахідки — в одному виклику, а не частина в `зн(…)`, частина в словнику над ним."""
        return dict(_РЕЄСТР.зн("K-PAL-03", _сила, суть, [ід], чому, reg=_РЕЄСТР.REGISTRY,
                               межа_людини=_вона, **решта),
                    **_мʼяко, бік="код", слот=с, ярлик=ярлик, що_зняло_б=що_зняло_б)

    зн = []
    for r in речі:
        с = r.get("слот")
        сп = спец_слоти.get(с)
        if not isinstance(сп, dict):
            continue
        # нейтральна роль дуги не має — її позначає `тон_ролі` (доти `дуга` тут
        # була None, і гілка «кольорова річ на нейтральній ролі» нижче не спрацьовувала ніколи)
        дуга, роль = сп.get("дуга_тону") or сп.get("тон_ролі"), сп.get("роль")
        повна = (за_ід or {}).get(r.get("id")) or r
        lab = _КР.точка_кольору(повна)
        if _КР.межі_кольору(повна) is None:
            continue
        L, C, h = _КС.lch(lab) if lab is not None else (None, None, None)
        повна = dict(повна, lab=lab)
        # МЕТАЛ ПРИКРАСИ — НЕ КОЛІР СХЕМИ: золоті сережки під «тональною» діставали
        # «поза дугою», хоч пул їх брав як метал (рядок металу, K-PAL-11) — `тримає_дугу_схеми`
        # каже «так» обом. Нейтраль — так само (`нейтраль_меж`): законна під будь-яку схему.
        _нт = _КР.нейтраль_меж(повна)
        if _нт == "так" or _ПЛ.колір_металу(повна):
            continue
        схема = спец_слоти.get("_схема", "?")
        _без_нт = lambda річ=повна: _КО_.без_входу_кольору(
            "K-PAL-03", [(річ,)], перевірка="cannot_tell_item_holds_scheme_hue")
        if _нт == "невідомо" and дуга == "нейтраль" and роль in ("домінанта", "секундант"):
            зн.append(_без_нт())
            continue
        if _нт == "ні" and _КО_.не_вимір(повна):
            C = _КО_.межі_кольору(повна)[2]             # у текст — нижня межа хроми вікна
        if дуга == "нейтраль" and роль in ("домінанта", "секундант"):
            зн.append(_межа(
                r.get("id"), с,
                "схема «%s» тримає слот «%s» нейтральним, а річ має хрому %.0f" % (схема, с, C),
                ("роль слота задана схемою, яку обрала жінка" if _вона is not False
                 else "роль слота задана схемою, яку обрала не жінка — це порада, не межа"),
                "colour_on_neutral_role",
                заяви=[_ВМ.заява("scheme_slot_neutral_item_coloured", scheme=_схема_код(схема),
                                 slot=сл_код(с), chroma=round(C))],
                що_зняло_б=_пояснення_без_заміни("K-PAL-03")))
            continue
        if not (isinstance(дуга, (list, tuple)) and len(дуга) == 2 and дуга[0] is not None):
            continue
        lo, hi = float(дуга[0]), float(дуга[1])
        # ДУГА — ТА САМА, ЩО «У ДУЗІ» ПУЛУ: `palettes.тримає_дугу_схеми` над дугою
        # ролі слота й дугами всіх сімей схеми великих поверхонь (у пулі великої речі
        # стоять усі її сім'ї), вікно з силою зрізом кінця згасання. Колір-слово судиться вікном, не центром
        # Усе вікно в дузі — нема чого казати; частково чи «можливо нейтраль» — «без
        # входу» з полем `колір_не_вимір`; уся дуга вікна поза дугою — порушення.
        в_дузі = _ПЛ.тримає_дугу_схеми(
            повна, [(lo, hi)] + [tuple(д["дуга"]) for д in (сп.get("дуги_схеми") or ())])
        if в_дузі == "так":
            continue
        if в_дузі == "невідомо":
            зн.append(_без_нт())
            continue
        if в_дузі == "ні":
            зн.append(_межа(
                r.get("id"), с,
                "схема «%s»: слот «%s» (роль %s) тримає тон %.0f–%.0f°, колір речі поза дугою"
                % (схема, с, роль, lo, hi),
                ("дуга схеми — межа, а не порада: поза нею образ не тримає обраної схеми"
                 if _вона is not False else
                 "поза дугою образ не тримає схеми, але схему обрала не жінка — це порада, не межа"),
                заяви=[_ВМ.заява("item_hue_outside_scheme_arc", scheme=_схема_код(схема),
                                 slot=сл_код(с), role=_ВМ.код_або_невідомо("scheme_role", роль),
                                 arc=[round(lo), round(hi)], hue=round(h) if h is not None else None,
                                 chroma=round(C) if C is not None else None)],
                ярлик="outside_scheme_arc",
                що_зняло_б=_пояснення_без_заміни("K-PAL-03")))
    return зн

def _у_вікнах_палітри(_КРІЧ, x, вікна):
    """«так» / «ні» / «невідомо»: `колір_річ.у_вікнах_меж` над вікнами палітри `вікна` — дуги сімей, а сім'я
    очей — записом райдужки `вікна.очі`, тим самим вердиктом, яким K-PAL-02/13 кажуть «від очей»."""
    сім = вікна.get("сім_ї") or {}
    дуги = [a for ім, arcs in сім.items() if ім != "очі" for a in (arcs or ())]
    очі = вікна.get("очі") if "очі" in сім else None
    return _КРІЧ.у_вікнах_меж(x, вікна["L"], вікна["C"], дуги, очі=очі)

def _частка_місця(елемент):
    """Частка приобличчевого поля із запису місця (для заяви) або None, коли в записі лише факт типу."""
    частка = _МІСЦЕ.біля_обличчя_відоме(елемент)
