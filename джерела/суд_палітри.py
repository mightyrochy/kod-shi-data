def кольори_образу(речі, за_ід=None):
    """[(річ, слот, L, C, h, near)] для відомих меж; L, C, h — None для інтервалу; near — зібрана річ, з якої
    бік межі «біля обличчя» читають `місце_речі.бік_межі` (True / False,
    None — не певний чи невідомий), сталої класу слота правила не підставляють.

    `за_ід` обовʼязковий із тієї самої причини, що в `акцент_образу`: рядок пулу,
    який їде моделі, не несе `lab`, і рахувати колір по ньому означало б судити
    дефолтний сірий (див. `bridge.каталог_останнього_пакета`).
    Місце береться зі зібраної речі зі збереженням її запису й слова стилістки;
    картка каталогу доповнює відсутні поля.
    """
    out = []
    for r in (речі or ()):
        повна = (за_ід or {}).get(r.get("id")) or r
        lab = _КР.точка_кольору(повна)
        if _КР.межі_кольору(повна) is None:
            continue
        try: L, C, h = _КС.lch(lab) if lab is not None else (None, None, None)
        except (TypeError, ValueError, AttributeError): continue
        слот = r.get("слот")
        out.append((r, слот, L, C, h, dict(повна, **r)))
    return out

def палітра_образу(речі, спец_слоти, за_ід=None):
    """[знахідки] практикових прийомів над зібраним образом.

    Чекає в `спец_слоти` службові ключі, які кладе шов (`bridge._пакет_каталогу`):
    `_палітра` — вихід `palettes.палітра_практична` (вікна, найдальші, активні
    прийоми), `_контраст` — рівень контрасту особи. Без них правила мовчать, і це
    «без входу», а не «пройдено»: перевірка без палітри була б заглушкою,
    невідрізненною від зеленого вердикту. Саме це й показує третій чекліст
    (`суд_образу.ЧЕКЛІСТ_ПАЛІТРИ`), щоб мовчання було видно.

    Прийоми, що міряють РІЗНИЦЮ між кольорами речей (K-PAL-08, K-PAL-15, K-PAL-05,
    K-PAL-12), судять лише вимір: де колір речі — центр вікна слова,
    різниця береться інтервалом на межах вікон, а висновок, що на ньому не
    тримається, іде записом «без входу» з названим полем.
    """
    без, невідомі, можливі = _палітра_образу(речі, спец_слоти, за_ід, False)
    # ── НЕЙТРАЛЬ ВІКНА ПО ОБИДВА БОКИ МЕЖІ — ДВА ВАРІАНТИ (КОЛІР-НЕЙТРАЛЬ) ──
    # ЩО БУЛО. K-PAL-15/05/06/12 рахують лише КОЛЬОРОВІ речі, і нейтраль відсіювалась центром вікна
    # слова: з 1 158 речей-слів каталогу пакета стенда нейтраль вікном «невідомо» в 646 (центр «так»
    # 293, «ні» 353; `проби/колір_нейтраль.py`). Виключити «можливо» нейтраль хибно (K-PAL-06 бачив би
    # один колір там, де їх два), включити — теж. ЩО СТАЛО. Суд іде двічі — без «можливих» і з ними
    # (`_нейтраль_межі` вікном, як у K-COL-06): де вирок правила однаковий, він стоїть (варіант без
    # «можливих»: їх не названо ні кольором, ні нейтраллю); де різний — запис «без входу» з полем
    # `колір_не_вимір` (п.4), а не вирок. Вимір — точкою, як доти: без «можливих» суд один.
    if можливі:
        з, невідомі_з, _ = _палітра_образу(речі, спец_слоти, за_ід, True)
        підпис = lambda зн, нв, пр: (sorted(z.get("сила") for z in зн if z.get("правило") == пр), bool(нв.get(пр)))
        for пр in _ПРАВИЛА_КОЛЬОРОВИХ:
            if підпис(без, невідомі, пр) != підпис(з, невідомі_з, пр):
                без = [z for z in без if z.get("правило") != пр]
                невідомі[пр] = невідомі.get(пр, []) + невідомі_з.get(пр, []) + [(e,) for e in можливі]
    for _пр, _пари in невідомі.items():
        if _пари:
            без.append(_КО_.без_входу_кольору(_пр, _пари, перевірка=_ЩО_КОДИ_ПАЛІТРИ[_пр]))
    return без

