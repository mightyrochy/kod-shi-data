_ПРАВИЛА_КОЛЬОРОВИХ = ("K-PAL-15", "K-PAL-05", "K-PAL-06", "K-PAL-12")

def _палітра_образу(речі, спец_слоти, за_ід, можливі):
    """(знахідки, невідомі, «можливі» елементи) `палітра_образу` на одному варіанті: `можливі` —
    чи рахувати річ-вікно, що «можливо» нейтраль, кольоровою. `невідомі` — {правило: пари} для
    записів «без входу»; «можливі» елементи — речі-вікна по обидва боки межі нейтралі."""
    П = (спец_слоти or {}).get("_палітра")
    if not isinstance(П, dict) or not П.get("вікна"):
        return [], {}, []
    рівень = (спец_слоти or {}).get("_контраст")
    # НАМІР ТУТ НЕ ЧИТАЄТЬСЯ, І ЦЕ НЕ ПРОПУСК: `palettes.прийоми` уже склав список
    # активних прийомів ІЗ НАМІРОМ (колор-блок і драматизація залежать від нього),
    # тож питати намір удруге означало б завести другого суддю тієї самої умови.
    активні = {x["прийом"] for x in (П.get("прийоми") or []) if x.get("активний")}
    далекі = (П.get("найдальші") or {}).get("вікна")
    гучно = _РЕЄСТР.C["hi_C"]
    зн = []

    def _дод(правило, сила, ярлик, суть, чому, зняло_б, речі_, слот=None, **решта):
        """Додає знахідку ПРИЙОМУ ПАЛІТРИ до `зн` з полями судді.

        Силу, регістр, вагу, `блокує` й слово репліки дає `реєстр_сила.зн` з реєстром ядра
        (Е3-сила-правила, п.1а): сила прийому — корпусна (тема-2 §K-PAL), і власні вага,
        регістр чи впевненість тут зробили б цей суддя другим джерелом поруч із конструктором.
        `решта` — параметри конструктора (`заяви`, `ремонт_заяви`, `ламається`); `бік="код"` —
        бо прийом читається з самої схеми палітри, не з фото."""
        зн.append(dict(_РЕЄСТР.зн(правило, сила, суть, [x for x in речі_ if x], чому,
                                  reg=_РЕЄСТР.REGISTRY, **решта),
                       бік="код", слот=слот, ярлик=ярлик, що_зняло_б=зняло_б))

    точки = кольори_образу(речі, за_ід)
    # НЕЙТРАЛЬ І МЕТАЛ ВИХОДЯТЬ ІЗ-ПІД ЦИХ ПРАВИЛ, і з тієї самої причини, що в
    # `схема_образу`: нейтраль законна під будь-яку схему (K-COL-06), а фурнітуру
    # судить метал палітри (K-PAL-11), не дуга сім'ї.
    ел = {id(t[0]): _елемент_точки(t, за_ід) for t in точки}
    нв = lambda t: _КО_.не_вимір(ел[id(t[0])])
    кол = lambda t: _КР.не(_КР.нейтраль_меж(ел[id(t[0])]))
    кольорові = [t for t in точки if (кол(t) == "так" or (можливі and кол(t) == "невідомо"))
                 and not _метал_точки(t, за_ід)]
    можливі_ел = [ел[id(t[0])] for t in точки if кол(t) == "невідомо"
                  and not _метал_точки(t, за_ід)]
    # ── ПРИЙОМИ НАД РІЧЧЮ — «ТАК / НІ / НЕВІДОМО» ВІКНОМ СЛОВА (КОЛІР-ВІКНО-СУД) ──
    # ЩО БУЛО. K-PAL-09/14/10 (колір у вікнах палітри чи найдальших), K-PAL-02 і K-PAL-13 (тон у
    # дузі очей) і K-PAL-07 (сім'я великої речі) питали точку `_кольори_образу`, а для кольору зі
    # слова точка — центр вікна: «синій» ставав «кольором поза палітрою» чи «не від очей» лише
    # тому, що центр вікна туди впав. ЩО СТАЛО. Річ-вікно судиться всім вікном
    # (`колір_річ.нейтраль_меж`, `у_вікнах_меж`, `у_дугах_кола`): вирок — коли його дає кожна
    # точка вікна, «невідомо» — запис «без входу» з полем `колір_не_вимір` (п.4, п.18). Вимір —
    # точкою, як доти. `кольорові` (K-PAL-15/05/06/12 — різниця між речами) — двома варіантами
    # «можливо» нейтралі (`палітра_образу`).
    _у_в = lambda t, вв: _у_вікнах_палітри(_КР, ел[id(t[0])], вв) if вв else "ні"
    кандидати = [t for t in точки if кол(t) != "ні" and not _метал_точки(t, за_ід)]
    поза_в = {id(t[0]): _КР.і(кол(t), _КР.не(_у_в(t, П["вікна"]))) for t in кандидати}
    поза_палітрою = [t for t in кандидати if поза_в[id(t[0])] == "так"]
    може_поза = [t for t in кандидати if поза_в[id(t[0])] == "невідомо"]
    # ── РІЗНИЦЯ МІЖ КОЛЬОРАМИ РЕЧЕЙ — ЛИШЕ НА ВИМІРІ ──
    # K-PAL-08, K-PAL-15, K-PAL-05 і K-PAL-12 міряють РІЗНИЦЮ між кольорами речей:
    # розмах і крок світлоти, розведення тону. Колір зі слова — центр вікна, і
    # різниця між ним і сусідом — наслідок побудови. Де хоч один колір не вимір
    # (`колір_образу.не_вимір`), різниця — інтервал на межах вікон
    # (`межі_кольору`, `розкид_осі`, `розкид_тону`): висновок, що тримається на
    # всьому інтервалі, стоїть із поміткою «на рівні вікон, не виміру»; решта —
    # запис «без входу» з названим полем. Для вимірів інтервал — точка, тож образ
    # самих вимірів судиться рівно як доти (ті самі пороги, той самий текст).
    # ── ГУЧНІСТЬ РЕЧІ — МЕЖАМИ ВІКНА, А НЕ ХРОМОЮ ЦЕНТРУ (КОЛІР-Р4-2б) ──
    # ЩО БУЛО. K-PAL-15 («два гучні»), K-PAL-05 (лічба гучних), K-PAL-06 і K-PAL-12 рахували річ
    # гучною за `t[3] >= hi_C` — хромою точки, а для кольору зі слова точка — центр вікна:
    # «зелений» (центр C* 52, виміри того самого слова — медіана 22–26) витрачав бюджет гучних,
    # хоч K-COL-02 (`колір_хрома`) і K-ACC-01 його вже не рахували. ЩО СТАЛО. Гучність — одна,
    # `колір_річ.гучність_меж`: «так» — уся хрома вікна над `hi_C` (вимір — як доти, точкою),
    # «ні» — уся під ним, «можливо» — висновок, що на ній стоїть, іде записом «без входу».
    гуч = lambda t: гучність_меж(ел[id(t[0])])
    невідомі = {}

    def _розмах(ts):
        """(мін, макс) розмаху світлоти набору: для вимірів — одне число двічі."""
        м = [_КО_.межі_кольору(ел[id(t[0])]) for t in ts]
        return (max(0.0, max(x[0] for x in м) - min(x[1] for x in м)),
                max(x[1] for x in м) - min(x[0] for x in м))

    def _понад(інт, поріг):
        """«так» / «ні» / «невідомо»: чи величина з інтервалом `інт` БІЛЬША за поріг."""
        return "так" if інт[0] > поріг else ("ні" if інт[1] <= поріг else "невідомо")

    def _нижче(інт, поріг):
        """«так» / «ні» / «невідомо»: чи величина з інтервалом `інт` МЕНША за поріг."""
        return "так" if інт[1] < поріг else ("ні" if інт[0] >= поріг else "невідомо")

    def _слова_розмаху(інт, бік):
        """«53» для виміру; «щонайменше 50» / «щонайбільше 28» для інтервалу на вікнах."""
        if abs(інт[1] - інт[0]) < 1e-9:
            return "%.0f" % інт[0]
        return ("щонайменше %.0f" % інт[0]) if бік == "понад" else ("щонайбільше %.0f" % інт[1])

    # ── K-PAL-14 / K-PAL-09: ЩО НОСИТИ БІЛЯ ОБЛИЧЧЯ ─────────────────────────
    # «Кольори палітри біля обличчя; кольори поза палітрою — у слоти далі від
    # обличчя» (K-PAL-09, default) і «найдальші — область із усіма осями,
    # оберненими проти домінанти» (K-PAL-14, hint).
    # ВОНИ НЕ ВИКЛЮЧАЮТЬ ОДНЕ ОДНОГО, І ЦЕ РІШЕННЯ, ЗМІНЕНЕ ПІД ЧАС ПРАВКИ.
    # Перша редакція давала на річ рівно одне з двох («14 названо — 09 мовчить»),
    # і це виявилось хибним із двох боків. По суті: корпус пов'язує їх ПРЯМО —
    # «labelled furthest, not forbidden; K-PAL-08 and K-PAL-09 say how to carry
    # them anyway», тобто 14 називає колір, а 09 каже, куди його подіти; разом
    # вони одна порада, поодинці — половина. По факту: взаємне виключення лишало
    # K-PAL-09 самий залишок (тони, що не лежать ні у вікнах палітри, ні в
    # найдальших) — на стенді це порожня множина, і правило `default`-сили
    # мовчало б на кожному живому вході. Одне правило — один рядок у вердикті
    # (`знахідки_вердикту` зливає за `правило`), тож два рядки тут — це два різні
    # твердження, а не дубль.
    без_місця = []
    for t in поза_палітрою + може_поза:
        r, с, L, C, h, near = t
        бік = _МІСЦЕ.бік_межі(near)
        if бік is None:
            без_місця.append(r)             # бік межі не певний чи невідомий — вирок не стоїть
            continue
        if not бік:
            continue                        # далеко від обличчя — K-PAL-09 це й дозволяє
        if поза_в[id(r)] == "невідомо":
            невідомі.setdefault("K-PAL-09", []).append((ел[id(r)],))
            continue
        _в14 = _у_в(t, далекі)
        if _в14 == "невідомо":
            невідомі.setdefault("K-PAL-14", []).append((ел[id(r)],))
        if _в14 == "так":
            _дод("K-PAL-14", "hint", "farthest_colour_near_face",
                 "«%s» стоїть біля обличчя, а її колір лежить у найдальшій від ваших осей "
                 "області (%s): жодної спільної характеристики з вами"
                 % (с or ТИПОВИЙ_СЛОТ, (П.get("найдальші") or {}).get("словами") or "всі осі обернені"),
                 "практики дають «найдальші» як відповідь на «чого уникати»; це не заборона — "
                 "K-PAL-08 і K-PAL-09 кажуть, як їх усе ж нести",
                 _пояснення_без_заміни("K-PAL-14"),
                 [r.get("id")], слот=с,
                 заяви=[_ВМ.заява("farthest_colour_near_face", slot=сл_код(с))])
        _дод("K-PAL-09", "default", "off_palette_near_face",
             "«%s» стоїть біля обличчя, а її колір поза вікнами вашої палітри"
             % (с or ТИПОВИЙ_СЛОТ,),
             "індукція локальна (Chevreul: найсильніша на лінії контакту), тому практики "
             "тримають кольори поза палітрою далі від обличчя",
             _пояснення_без_заміни("K-PAL-09"),
             [r.get("id")], слот=с,
             заяви=[_ВМ.заява("off_palette_colour_near_face", slot=сл_код(с), nearness=_частка_місця(near))])

    # Місце речі невідоме (запис `місце_речі` без виміру, слова стилістки й факту слота) — це «без входу» з
    # названим полем, а не «далеко» чи «біля» зі сталої класу (корінь Е3-місце-речі).
    for _пр in ("K-PAL-09", "K-PAL-14"):
        if без_місця:
            зн.append(_брак_входу(_пр, [dict(річ=r.get("id")) for r in без_місця], ("місце_речі.біля_обличчя",)))
    # ── K-PAL-08: КОНТРАСТ ЯК НОСІЙ ─────────────────────────────────────────
    # «Колір поза палітрою можна нести, якщо контраст образу збігається з
    # контрастом людини» (Lamport, hint). Отже правило говорить рівно тоді, коли
    # такий колір В ОБРАЗІ Є: інакше воно не має про що судити. Смуги збігу —
    # ті самі числа K-PAL-15, якими код уже породжує трійки, а не нові.
    if (поза_палітрою or може_поза) and len(точки) >= 2:
        розмах = _розмах(точки)
        бік = "понад" if рівень == "низький" else "нижче"
        стан = (_понад(розмах, _ПЛ.РОЗМАХ_НИЗЬКОГО) if рівень == "низький" else
                _нижче(розмах, _ПЛ.РОЗМАХ_ВИСОКОГО) if рівень == "високий" else "ні")
        if стан == "так" and not поза_палітрою:
            стан = "невідомо"               # контраст не той, а чи є колір поза палітрою — вирішує вікно
        if стан == "невідомо":
            невідомі["K-PAL-08"] = [(ел[id(t[0])],) for t in точки if нв(t)]
        if стан == "так":
            _дод("K-PAL-08", "hint", "off_palette_no_carrier",
                 "в образі є колір поза палітрою, а контраст образу (розмах світлоти %s) "
                 "не збігається з вашим (%s) — нести його нема на чому%s"
                 % (_слова_розмаху(розмах, бік), рівень,
                    "; на рівні вікон, не виміру" if any(нв(t) for t in точки) else ""),
                 "Lamport: «easier to wear less flattering colours if you're wearing the right "
                 "contrast levels» — носієм чужого кольору є саме збіг контрастів",
                 _пояснення_без_заміни("K-PAL-08"),
                 [t[0].get("id") for t in поза_палітрою],
                 заяви=[_ВМ.заява("off_palette_colour_contrast_mismatch",
                                  lightness_range=[round(розмах[0]), round(розмах[1])],
                                  her_level=_ВМ.код_або_невідомо("contrast_level", рівень),
                                  **({"on_windows": True} if any(нв(t) for t in точки) else {}))])

    # ── K-PAL-15: ПОЄДНАННЯ — ТА САМА ЛОГІКА, ЩО В ТРІЙКАХ ──────────────────
    # Код видає жінці трійки (`palettes.поєднання`); той самий набір перевірок
    # (`palettes.набір_законний`) тепер судить те, що склала модель. Один емітент
    # логіки, не два: інакше система пропонувала б те, що сама відхиляє.
    # ГОЛОСИ, А НЕ РЕЧІ (ФОКУС-2; аудит/ПРОДУКТ.md п.4, п.17). Трійка — три
    # РІЗНІ кольори; в образі зелена сумка й зелені сережки — ОДИН колір, повторений у двох
    # рознесених точках, тобто відлуння, якого вимагає K-COMP-05. Доти логіка трійки лічила
    # речі: сумка й сережки того самого тону ставали «двома гучними кольорами», а крок
    # світлоти між ними — «кольори злипаються», і ремонт знімав колір (живий ПІСЛЯ ФОКУС-1:
    # `more_than_one_loud_colour` — 11 з 27 кольорових образів, ж1 o6, ж4 o2). Тепер речі
    # спершу зводяться в голоси тоном (дуга `_СУСІДНІ_ТОНИ`, та сама, що в K-COL-05 і в
    # групах фокусів K-CRA-02); на слові голоси зводить лише «так», розводить лише «ні»,
    # а висновок, що стоїть на парі «невідомо», іде записом «без входу». Логіка
    # трійки судить представників голосів (найгучнішу річ кожного), розмах — увесь образ.
    поруч_т = lambda a, b: _КО_.відношення(ел[id(a[0])], ел[id(b[0])], "same_hue", певність=False)
    голоси = []
    for t in кольорові:
        g = next((g for g in голоси if поруч_т(g[0], t) == "так"), None)
        if g is None:
            голоси.append([t])
        else:
            g.append(t)
    голос = {id(t): i for i, g in enumerate(голоси) for t in g}
    предст = [max(g, key=lambda t: _КР.межі_кольору(ел[id(t[0])])[2]) for g in голоси]
    _заяви_з = []
    законно, чому_ні = True, None
    if len(кольорові) >= 2 and not any(нв(t) for t in кольорові):
        # Крок і гучність — по голосах, розмах — по ВСІХ кольорових речах: доти
        # розмах брався з представників, і з одним голосом (сумка й сережки того самого
        # тону L20 і L75) не перевірявся зовсім, хоч гілка вікон міряла весь образ.
        законно, чому_ні, _заяви_з = _ПЛ.набір_законний_заява(
            [(t[2], t[3]) for t in предст], рівень, світлоти=[t[2] for t in кольорові])
    elif len(кольорові) >= 2:
        # Ті самі три перевірки, що в `palettes.набір_законний`, і так само УСІ, не перша
        # Але крок і розмах — на інтервалах вікон. Гучність — властивість
        # КОЖНОЇ речі (хрома проти стелі), а не різниця між ними, і лишається як є.
        # Пари — лише між РІЗНИМИ голосами; пара, чий тон «невідомо», може бути тим
        # самим кольором, тож «крок замалий» чи «два гучні» на ній — теж «невідомо».
        _крок = _РЕЄСТР.C["step_min"]
        _пари = [(a, b) for i, a in enumerate(кольорові) for b in кольорові[i + 1:]
                 if голос[id(a)] != голос[id(b)]]
        _тон = [поруч_т(a, b) for a, b in _пари]
        _кроки = []
        for (a, b), т in zip(_пари, _тон):
            # «крок замалий» — заперечення класу `value_step` API відношень (КОЛІР-Р4)
            к = {"так": "ні", "ні": "так"}.get(_КО_.відношення(ел[id(a[0])], ел[id(b[0])], "value_step"), "невідомо")
            _кроки.append("невідомо" if к == "так" and т == "невідомо" else к)
        # «два гучні» — лише коли обидві речі гучні напевно; «можливо» в парі робить його
        # «невідомо», як і тон «невідомо»; пара з тихою річчю — не про гучних
        _гучні_пари = [(п, т if {гуч(п[0]), гуч(п[1])} == {"так"} or т != "ні" else "невідомо")
                       for п, т in zip(_пари, _тон) if not {гуч(п[0]), гуч(п[1])} & {"ні", None}]
        _р = _розмах(кольорові)
        _межа = _ПЛ.РОЗМАХ_НИЗЬКОГО if рівень == "низький" else _ПЛ.РОЗМАХ_ВИСОКОГО
        _рст = (_понад(_р, _межа) if рівень == "низький" else
                _нижче(_р, _межа) if рівень == "високий" else "ні")
        _чому = []
        if "так" in _кроки:
            _чому.append("кроку світлоти між кольорами менше за %.0f L* (на рівні вікон, не виміру)" % _крок)
            _заяви_з.append(_ВМ.заява("colour_step_below_min", step_min=round(_крок), on_windows=True))
        if any(т == "ні" for _, т in _гучні_пари):
            _чому.append("гучних кольорів більше за один (хрома ≥ %.0f)" % гучно)
            _заяви_з.append(_ВМ.заява("more_than_one_loud_colour", loud_from=round(гучно)))
        if _рст == "так":
            _чому.append("розмах світлоти %s L* при %s контрасті людини (стеля %.0f / підлога %.0f; "
                         "на рівні вікон, не виміру)"
                         % (_слова_розмаху(_р, "понад" if рівень == "низький" else "нижче"), рівень,
                            _ПЛ.РОЗМАХ_НИЗЬКОГО, _ПЛ.РОЗМАХ_ВИСОКОГО))
            _заяви_з.append(_ВМ.заява("lightness_range_off_her_contrast",
                                      lightness_range=[round(_р[0]), round(_р[1])],
                                      her_level=_ВМ.код_або_невідомо("contrast_level", рівень),
                                      limit=round(_межа), on_windows=True))
        if _чому:
            законно, чому_ні = False, "; ".join(_чому)
        elif ("невідомо" in _кроки or any(т == "невідомо" for _, т in _гучні_пари)
              or _рст == "невідомо"):
            невідомі["K-PAL-15"] = ([(ел[id(a[0])], ел[id(b[0])]) for (a, b), к in zip(_пари, _кроки)
                                    if к == "невідомо"]
                                   + [(ел[id(a[0])], ел[id(b[0])]) for (a, b), т in _гучні_пари
                                      if т == "невідомо"]
                                   + ([(ел[id(t[0])],) for t in кольорові if нв(t)]
                                      if _рст == "невідомо" else []))
    if len(кольорові) >= 2:
        if not законно:
            # Ремонт — лише там, де корпус велить міняти (аудит/ПРОДУКТ.md п.4, п.17). Два РІЗНІ гучні
            # кольори K-COL-02 не забороняє («≤1–2 highly saturated elements», тема-4:290), а
            # понад два судить сам K-COL-02 (`loud_elements_over_budget`, `бюджет_і_відлуння`).
            # Тож «гучних більше одного» — інформація без ремонту, але лише коли це ЄДИНА вада:
            # крок і розмах світлоти поруч із нею ремонт просять, як доти.
            _гучно_лише = all(з.get("code") == "more_than_one_loud_colour" for з in _заяви_з)
            _дод("K-PAL-15", "hint", "colours_outside_combinations",
                 "кольори образу разом не тримають тієї логіки, якою складені ваші поєднання: %s" % чому_ні,
                 "стиліст видає не палітру, а готові трійки; вони будуються кроком світлоти "
                 "(K-COL-01), бюджетом хроми (K-COL-02) і вашим рівнем контрасту",
                 ("два гучні кольори — у межах бюджету K-COL-02 (1–2): ремонту не просить"
                  if _гучно_лише else _пояснення_без_заміни("K-PAL-15")),
                 [t[0].get("id") for t in кольорові],
                 заяви=[_ВМ.заява("colours_off_her_combination_logic")] + _заяви_з)

    # ── K-PAL-02: АКЦЕНТ БЕРЕТЬСЯ ВІД ОЧЕЙ ПЕРШИМ ────────────────────────────
    # «Повторити колір очей як акцент … завжди доступний, ПЕРШИЙ за порядком»
    # (R-COL-17, Perrett 2023: одяг обирають до райдужки, не до шкіри; 200
    # учасників, T2). У пулі це вже діє рангом рядка, але ранг розв'язує лише
    # НІЧИЮ — а тут питання інше й перевірне: слот, якому СХЕМА дала роль акценту,
    # несе колір із сім'ї очей чи чужий. Мовчимо, коли акцент нейтральний: «нема
    # акценту» — це K-PAL-18, інше правило й інший ремонт.
    # ІНФОРМАЦІЯ, НЕ РЕМОНТ (ФОКУС-2; аудит/ПРОДУКТ.md п.4, п.17). Корпус
    # (тема-2:1848, K-PAL-02 default): «repeat the eye colour as accent … Always available;
    # first in order» — це ПОРЯДОК прийомів, а не вада чужого акценту: ніде не сказано, що
    # акцент поза сім'єю очей хибний чи що його прибирати. Доти знахідка везла ремонт
    # `accent_in_eye_family`, і ремонт міняв акцент схеми на річ із дуги очей — на
    # ж4 (очі 25–85°) зелену сумку на коричневу, тобто колір схеми на нейтраль: живий
    # ПІСЛЯ ФОКУС-1, 16 з 43 кольорових образів, де вона стояла, втратили колір. Тепер
    # знахідка лишає заяву (стилістка знає, що є перший за порядком прийом), а ремонту
    # не везе — вибір кольору акценту за схемою, її бажанням чи свідомим ходом стилістки.
    очі_дуги_02 = (П["вікна"].get("сім_ї") or {}).get("очі") or []
    if очі_дуги_02:
        for t in кандидати:
            r, с, L, C, h, near = t
            сп = (спец_слоти or {}).get(с)
            if not isinstance(сп, dict) or сп.get("роль") != "акцент":
                continue
            _н02 = _КР.і(кол(t), _КР.не(_КР.у_відлунні_очей(ел[id(r)], П["вікна"].get("очі"))))
            if _н02 == "невідомо":
                невідомі.setdefault("K-PAL-02", []).append((ел[id(r)],))
            if _н02 != "так":
                continue
            _дод("K-PAL-02", "hint", "accent_not_from_eyes",
                 "слот «%s» несе акцент поза сім'єю ваших очей (%s)"
                 % (с, "; ".join("%.0f–%.0f°" % (a[0], a[1]) for a in очі_дуги_02)),
                 "Perrett 2023: одяг обирають до райдужки, не до шкіри; практики ставлять "
                 "перегук очей першим прийомом — це колір, який у людини вже є",
                 "акцент у сім'ї очей (%s) у слоті «%s»"
                 % ("; ".join("%.0f–%.0f°" % (a[0], a[1]) for a in очі_дуги_02), с),
                 [r.get("id")], слот=с,
                 заяви=[_ВМ.заява("accent_not_from_eyes", slot=сл_код(с), hue=round(h) if h is not None else None,
                                  eye_arcs=[[round(a[0]), round(a[1])] for a in очі_дуги_02])])

    # ── K-PAL-05 / 06: ЯКИЙ ПРИЙОМ ОБРАЗ РЕАЛІЗУЄ — І ЧИ ВІН ЇЇ ──────────────
    # Прийоми — оператори з УМОВОЮ («середній/високий контраст», «на м'якій людині
    # обидва приглушені», «для низького контрасту акцент приглушений»). Умова
    # рахувалась у `palettes.прийоми` і вирішувала лише, чи називати прийом
    # доступним; що образ РЕАЛІЗУЄ саме цей прийом і порушує саме його умову, не
    # питав ніхто. Тут образ спершу ВПІЗНАЄТЬСЯ, а тоді перевіряється умова
    # впізнаного — не всіх підряд: інакше на кожен образ висипалось би по чотири
    # hint-и про прийоми, яких у ньому нема.
    if len(кольорові) >= 2:
        позиція = (П.get("осі") or {}).get("позиція") or {}
        if позиція.get("chroma") is None:
            зн.append(_брак_входу("K-PAL-05", [t[0] for t in кольорові], ("chroma",)))
        else:
            м_яка = позиція["chroma"] < 0
            # Розведення тону між речами — на тому самому колі художника, що й палітра; для
            # вікна слова — інтервал на дугах вікон: комплемент стверджується, лише
            # коли ВСЯ пара дуг розведена не менше нижнього краю дуги комплементу (`колір_тон.RELATIONS`, 150°); «може бути» при зайвих гучних — «без входу».
            # Гучність — кожної речі. Вердикт і Δ кола — клас «complementary» API відношень з мірою
            # (КОЛІР-Р4) і на вимірі теж: доти гілка вимірів міряла тон точкою сама.
            _т = [(ел[id(a[0])], ел[id(b[0])])
                  + _КО_.відношення(ел[id(a[0])], ел[id(b[0])], "complementary", міра=True, певність=False)
                  for i, a in enumerate(кольорові) for b in кольорові[i + 1:]]
            # гучні — `гучність_меж`: «так» лічиться, «можливо» — лише в межі «без входу»
            гучних = sum(1 for t in кольорові if гуч(t) == "так")
            _може = [t for t in кольорові if гуч(t) == "можливо"]
            треба = 0 if м_яка else 1
            if (гучних + len(_може) > треба and not any(р[2] == "так" for р in _т)
                    and any(р[2] == "невідомо" for р in _т)):
                невідомі["K-PAL-05"] = [(р[0], р[1]) for р in _т if р[2] == "невідомо"]
            дельти = [р[3][0] for р in _т if р[2] == "так"]
            # нижній край дуги комплементу — з одного визначення дуг відношень (`колір_тон.RELATIONS`,
            # 180 ± 30), а не голе 150 поруч (корінь Е3-одна-величина, дошка 13376)
            _ц, _ш = _КТ_.RELATIONS["complementary"]
            _край_комплементу = _ц - _ш
            if any(d >= _край_комплементу for d in дельти) and гучних <= треба < гучних + len(_може):
                # комплемент є, а чи гучних понад дозволені — вирішує річ-вікно «можливо»
                невідомі["K-PAL-05"] = невідомі.get("K-PAL-05", []) + [(ел[id(t[0])],) for t in _може]
            if any(d >= _край_комплементу for d in дельти):
                # K-PAL-05 приглушена комплементарна: «один із двох приглушений або малий;
                # на м'якій людині — обидва приглушені»
                if гучних > треба:
                    _дод("K-PAL-05", "default", "complementary_not_muted",
                         "образ веде комплементарна пара (розведення тону %s%.0f°), а гучних кольорів %d "
                         "при дозволених %d%s%s" % ("щонайменше " if any(нв(t) for t in кольорові) else "",
                                                    max(дельти), гучних, треба,
                                                    " — ваша палітра м'яка, тут приглушені обидва" if м_яка else "",
                                                    "; на рівні вікон, не виміру"
                                                    if any(нв(t) for t in кольорові) else ""),
                         "прийом дозволяє комплемент лише коли один із двох приглушений або малий; "
                         "на м'якій людині — обидва (K-COL-03, бюджет хроми)",
                         _пояснення_без_заміни("K-PAL-05"),
                         [t[0].get("id") for t in кольорові if гуч(t) == "так"],
                         заяви=[_ВМ.заява("complementary_pair_not_muted", hue_gap=round(max(дельти)), loud=гучних,
                                          allowed=треба, **({"soft_palette": True} if м_яка else {}),
                                          **({"on_windows": True} if any(нв(t) for t in кольорові) else {}))])
            # K-PAL-04 (аналогова) ВЕРДИКТУ ТУТ НЕ МАЄ, І ЦЕ РІШЕННЯ, А НЕ ПРОПУСК.
            # Перша редакція давала знахідку «аналогова пара, а прийом не в наборі для
            # вашого контрасту» — і гілка виявилась недосяжною за побудовою: корпус не
            # вимикає аналогову на жодному контрасті («низький/середній; на високому
            # крок ΔL обовʼязковий»), тож умова «прийом недоступний» хибна завжди.
            # А те, що правило справді стверджує над образом — крок світлоти між
            # сім'ями — уже міряє `набір_законний` (K-PAL-15) тим самим `step_min`
            # K-COL-01; другий рядок про те саме число був би не другим правилом, а
            # тим самим удвічі. K-PAL-04 діє там, де має: він ПОРОДЖУЄ аналогові трійки
            # (`palettes.поєднання` з ід="K-PAL-04") і стоїть у пакеті й описі серед
            # прийомів, доступних цій людині, зі своєю умовою.

    # ── K-PAL-06: НЕЙТРАЛІ ПЛЮС ОДИН АКЦЕНТ ──────────────────────────────────
    # «Нейтралі людини + один акцент, перший — сім'я очей; дефолт для високого
    # контрасту; ДЛЯ НИЗЬКОГО АКЦЕНТ ПРИГЛУШЕНИЙ» (K-COL-03; palettehunt; Lamport).
    # ЧОМУ ПОЗА ЛАНЦЮЖКОМ ВПІЗНАВАННЯ ВИЩЕ, І ЦЕ ВИПРАВЛЕННЯ, А НЕ СМАК: той
    # ланцюжок стоїть під `len(кольорові) >= 2`, бо впізнає ВІДНОШЕННЯ між двома
    # кольорами (комплемент, сусідні сім'ї). А цей прийом упізнається якраз
    # ОДНИМ кольоровим на тлі нейтралей — тобто під тією умовою він недосяжний за
    # побудовою. Спіймано пробою: образ «гучна сорочка + три нейтралі» на
    # низькоконтрастній жінці проходив мовчки.
    # Гучність акценту — `гучність_меж`: вікно слова — «так» лише всією хромою над
    # стелею (у текст — нижня межа), «можливо» — «без входу»; вимір — як доти.
    _г06 = гуч(кольорові[0]) if len(кольорові) == 1 and len(точки) > 1 and рівень == "низький" else None
    if _г06 == "можливо":
        невідомі["K-PAL-06"] = [(ел[id(кольорові[0][0])],)]
    if _г06 == "так":
        акц = кольорові[0]
        _C06 = _КО_.межі_кольору(ел[id(акц[0])])[2]
        _дод("K-PAL-06", "default", "accent_not_muted_low_contrast",
             "образ — ваші нейтралі плюс один акцент, і акцент гучний (хрома %s%.0f ≥ %.0f) "
             "при низькому контрасті" % ("щонайменше " if нв(акц) else "", _C06, гучно),
             "прийом дає для низького контрасту приглушений акцент: гучний на низькому "
             "контрасті читається не як акцент, а як чужа пляма",
             _пояснення_без_заміни("K-PAL-06"),
             [акц[0].get("id")], слот=акц[1],
             заяви=[_ВМ.заява("loud_accent_on_low_contrast", chroma=round(_C06), loud_from=round(гучно),
                              **({"on_windows": True} if нв(акц) else {}))])

    # ── K-PAL-07: КОЛОР-БЛОК ВИМКНЕНО НА НИЗЬКОМУ КОНТРАСТІ ─────────────────
    # `palettes.прийоми` вже вирішує, чи прийом доступний ЦІЙ людині («statement
    # або високий контраст; вимкнено на низькому»). Доти це рішення нікуди не
    # їхало. Тут воно судить образ: дві-три кольорові сім'ї у великих слотах — це
    # і є колор-блок, і на низькому контрасті під conventional його нема в наборі.
    # СІМ'Ї ВЕЛИКИХ РЕЧЕЙ — СЕКТОРИ КОЛА, ТА САМА ЛІЧБА, ЩО K-COMP-03 (2.14-А, `колір_річ.сім_ї_тонів`).
    # Доти — дуги `palettes.СІМ_Ї` CIELAB зі злиттям `same_hue` «за першою річчю голосу»: бірюза h200 і нейві h285
    # (57° кола) були однією «синьою», а тон у прогалині дуг (h245, h12, h147, h192) — None і мовчки випадав. Річ,
    # чий колір чи нейтральність невідомі, і вікно слова без певної сім'ї — «?»: вирок «≥2 сім'ї» —
    # лише на відомих.
    _великі = [t for t in кандидати if t[1] in ВЕЛИКІ_СЛОТИ]
    _тонові = [t for t in _великі if кол(t) == "так"]
    _групи07, _без07 = _КР.сім_ї_тонів([ел[id(t[0])] for t in _тонові])
    сім_ї_великих = [назва for назва, _ in _групи07]   # список: дві групи можуть мати один сектор середини
    _невизн = [t for t in _великі if кол(t) == "невідомо"] + [_тонові[i] for i in _без07]
    if (len(сім_ї_великих) < 2 <= len(сім_ї_великих) + len(_невизн)) and "колор_блок" not in активні:
        невідомі["K-PAL-07"] = [(ел[id(t[0])],) for t in _невизн]
    if len(сім_ї_великих) >= 2 and "колор_блок" not in активні:
        _дод("K-PAL-07", "hint", "colour_block_low_contrast",
             "у великих слотах стоять %d кольорові сім'ї (%s) — це колор-блок, а він "
             "не в наборі прийомів для вашого контрасту під цим наміром"
             % (len(сім_ї_великих), ", ".join(sorted(сім_ї_великих))),
             "Imogen Lamport: колор-блок — виняток («unless heavy colour blocking»), "
             "не дефолт низького контрасту",
             _пояснення_без_заміни("K-PAL-07"),
             [t[0].get("id") for t in кольорові if t[1] in ВЕЛИКІ_СЛОТИ],
             заяви=[_ВМ.заява("colour_block_on_low_contrast",
                              families=[_ВМ.код_або_невідомо("hue_sector", x) for x in sorted(сім_ї_великих)])])

    # ── K-PAL-10: ПРИНТ ПРОТИ ПАЛІТРИ ───────────────────────────────────────
    # Корпус (тема-2:1856): «принт придатний, якщо його домінанта в палітрі і
    # внутрішній контраст ≈ контраст людини». Канал повернувся 16.09, коли річ
    # пулу дістала `колір`/`hex`: домінанту принту система тепер має — це той
    # самий представник кольору речі, яким її й судять скрізь. ДРУГОЇ ПОЛОВИНИ
    # ПРАВИЛА НЕМА І ЦЕ СКАЗАНО ВГОЛОС: внутрішній контраст принту фід не міряє,
    # тому знахідка говорить лише про домінанту й називає межу в `ламається`.
    for r, с, _, _, _, _ in поза_палітрою + може_поза:
        повна = (за_ід or {}).get(r.get("id")) or r
        віз = str(повна.get("візерунок") or "").strip().lower()
        if not віз or віз in ("solid", "однотонний"):
            continue
        if поза_в[id(r)] == "невідомо":
            невідомі.setdefault("K-PAL-10", []).append((ел[id(r)],))
            continue
        _дод("K-PAL-10", "default", "print_dominant_off_palette",
             "«%s» має візерунок «%s», а домінанта його кольору поза вікнами вашої палітри"
             % (с or ТИПОВИЙ_СЛОТ, віз),
             "Lamport 2018: принт придатний, коли його домінанта — ваш колір",
             _пояснення_без_заміни("K-PAL-10"),
             [r.get("id")], слот=с,
             заяви=[_ВМ.заява("print_dominant_off_palette", slot=сл_код(с),
                              pattern=_ВМ.код_або_невідомо("pattern", віз))],
             ламається="внутрішній контраст принту фід не міряє — судиться лише домінанта")

    # ── K-PAL-12: ДРАМАТИЗАЦІЯ М'ЯКОЇ ПАЛІТРИ ───────────────────────────────
    # «М'яку палітру робити драматичною контрастом світлоти, фактурою і блиском,
    # а не хромою» (Lamport 2019, hint). Прийом активний лише під statement при
    # chroma < 0 — і рівно тоді правило має що сказати: якщо образ пішов у гучний
    # колір замість світлоти, він драматизує не тим важелем.
    if "драматизація_м_якої" in активні and len(точки) >= 2:
        гучні = [t for t in кольорові if гуч(t) == "так"]
        розмах = _розмах(точки)
        # «можливо» гучна річ-вікно за вузького розмаху — теж «без входу»
        if (гучні and _нижче(розмах, 30) == "невідомо") or (
                not гучні and _нижче(розмах, 30) != "ні" and any(гуч(t) == "можливо" for t in кольорові)):
            невідомі["K-PAL-12"] = [(ел[id(t[0])],) for t in точки if нв(t)]
        if гучні and _нижче(розмах, 30) == "так":
            _дод("K-PAL-12", "hint", "drama_chroma_not_lightness",
                 "ваша палітра м'яка, а образ драматизується гучним кольором (хрома ≥ %.0f) "
                 "при розмаху світлоти лише %s L*%s"
                 % (гучно, _слова_розмаху(розмах, "нижче"),
                    "; на рівні вікон, не виміру" if any(нв(t) for t in точки) else ""),
                 "Lamport: м'яку палітру робить драматичною контраст світлоти, фактура і блиск, "
                 "а не хрома — гучний колір на м'якій людині читається як чужий, не як сміливий",
                 _пояснення_без_заміни("K-PAL-12"),
                 [t[0].get("id") for t in гучні],
                 заяви=[_ВМ.заява("drama_by_chroma_on_soft_palette", loud_from=round(гучно),
                                  lightness_range=[round(розмах[0]), round(розмах[1])],
                                  **({"on_windows": True} if any(нв(t) for t in точки) else {}))])

    # ── K-PAL-13: СИВИНА — ОЧІ СТАЮТЬ ГОЛОВНИМ АКЦЕНТОМ ─────────────────────
    # Прийом активний лише на ахроматичному волоссі (`palettes.прийоми`), і доти
    # це рішення не мало наслідку взагалі: на живому вході батарея не має профілю
    # з сивиною, тож гілка не виконувалась, а якби й виконалась — нікуди не йшла.
    # Тут вона судить: коли волосся не несе температури, єдиний акцент, що лишився
    # від рис, — сім'я очей, і образ без неї біля обличчя втрачає останній перегук.
    if "сивина" in активні:
        очі_дуги = (П["вікна"].get("сім_ї") or {}).get("очі") or []
        # тон у дузі очей і нейтраль — вікном слова: «так» / «ні» / «невідомо»
        _біля13 = [t for t in кандидати if _МІСЦЕ.бік_межі(t[5]) is True]
        _без_місця13 = [t for t in кандидати if _МІСЦЕ.бік_межі(t[5]) is None]
        біля = [t for t in _біля13 if кол(t) == "так"]
        _має13 = _КР.або("ні", *(_КР.і(кол(t), _КР.у_відлунні_очей(ел[id(t[0])], П["вікна"].get("очі")))
                                    for t in _біля13))
        _кол13 = _КР.або("ні", *(кол(t) for t in _біля13))
        має_очі = _має13 == "так"
        if очі_дуги and _біля13 and not має_очі and not (_має13 == "ні" and _кол13 != "невідомо"):
            невідомі["K-PAL-13"] = [(ел[id(t[0])],) for t in _біля13 if нв(t)]
        if очі_дуги and _без_місця13 and _має13 != "так":
            зн.append(_брак_входу("K-PAL-13", [dict(річ=t[0].get("id")) for t in _без_місця13],
                                  ("місце_речі.біля_обличчя",)))
        if очі_дуги and біля and _має13 == "ні":
            _дод("K-PAL-13", "default", "grey_hair_no_eye_accent",
                 "волосся не несе температури, тому головним акцентом лишаються очі — "
                 "а біля обличчя нема жодного кольору з їхньої сім'ї",
                 "Lamport 2026; Shop My Palette 2026: із сивиною контраст, глибина й хрома "
                 "м'якшають, сірий стає нейтраллю, а очі стають головним акцентом",
                 _пояснення_без_заміни("K-PAL-13"),
                 [t[0].get("id") for t in біля],
                 заяви=[_ВМ.заява("grey_hair_no_eye_colour_near_face")])
    return зн, невідомі, можливі_ел


def _лишити_стишити(гучні_т, схема_слоти=None, за_ід=None):
    """(keep, quiet, keep_by) K-COL-02 — ЯКИЙ гучний лишити, а які стишити (ФОКУС-3).

    Ремонт «лишити один гучний, решту стишити» не казав, ЯКИЙ: на ж6 р2 (fokus_2/ПІСЛЯ) модель
    знімала зелену сумку — акцент схеми, що відлунює в туфлях, — бо бюджет переповнювало
    волосся. Тут — те саме рішення, що K-CRA-02 (`суд_ремесло.фокуси_знахідка`): гучні речі
    групами одного тону (±15° кола художника, `суд_ремесло.ДУГА_ВІДЛУННЯ`, клас «same_hue»
    `колір_річ.відношення`; колір зі слова — «невідомо» не розводить); група ОГОЛОШЕНА, коли її річ стоїть в акцентному слоті схеми, що
    несе тон дуги (`схема_слоти`, "scheme"), чи це її явний вибір (`регістр_уваги.її_вибір`, "her_wish" — п.9). `keep` — оголошені речі,
    а коли оголошена одна, ще й один носій її тону (відлуння K-COMP-05: ≥2 точки); `quiet` —
    решта гучних, і зайві носії того самого тону теж: бюджет рахує речі. Коди слотів."""
    схема_слоти = set(схема_слоти or ())
    групи = []
    for t in гучні_т:
        e = _елемент_точки(t, за_ід)
        for g in групи:
            п = g["ел"][0]
            if _КО_.відношення(e, п, "same_hue", певність=False) != "ні":   # два виміри — «так» чи «ні»
                break
        else:
            g = dict(ел=[], оголошені=[], решта=[])
            групи.append(g)
        g["ел"].append(e)
        повна = (за_ід or {}).get(t[0].get("id")) or t[0]
        хто = {х for х, так in (("scheme", t[1] in схема_слоти),
                                ("her_wish", _РУ.її_вибір(повна))) if так}
        (g["оголошені"] if хто else g["решта"]).append((t[1], хто))
    keep, quiet, keep_by = set(), set(), set()
    for g in групи:
        луна = g["решта"][:1] if len(g["оголошені"]) == 1 else []
        keep |= {с for с, _ in g["оголошені"] + луна}
        quiet |= {с for с, _ in g["решта"] if (с, set()) not in луна}
        keep_by |= {х for _, хто in g["оголошені"] for х in хто}
    кд = lambda сс: sorted({сл_код(с) for с in сс if с})
    return кд(keep), кд(quiet - keep), sorted(keep_by)

def бюджет_і_відлуння(речі, F=None, за_ід=None, схема_слоти=None, *, повний_склад=False):
    """[знахідки] K-COL-02 (бюджет хроми) і K-COL-05 (відлуння) над ЗІБРАНИМ образом.

    Площі не потрібно: перше правило рахує ГУЧНІ елементи, друге — ЗОНИ. `F` —
    риси особи (`волосся*`, `оправа`): корпус K-COL-02 прямо каже «counting hair,
    counting eyewear frames», і без них бюджет рахувався б не за правилом.

    K-COL-05 порівнює тон РЕЧЕЙ і тому судить лише вимір: речі, чий
    колір — центр вікна слова, групуються на рівні вікон, а висновок, що на них
    не тримається, іде записом «без входу» з названим полем (`без_входу_кольору`).
    Повний склад ядра дає також речі без кольору. В іншому слоті така річ може відлунювати акценту.
    """
    гучно = _РЕЄСТР.C["hi_C"]
    точки = кольори_образу(речі, за_ід)
    if not точки:
        return []
    зн = []

    def _дод(правило, сила, ярлик, суть, чому, зняло_б, речі_, ремонт=None, слот=None, **решта):
        """Додає знахідку ПРАВИЛА КОЛЬОРУ до `зн` з полями судді.

        Силу, регістр, вагу, `блокує` й слово репліки дає `реєстр_сила.зн` з реєстром ядра
        (Е3-сила-правила, п.1а); `решта` — параметри конструктора (`вимір`, `поріг`, `заяви`,
        `ремонт_заяви`, `ламається`). Відмінність від однойменної в прийомах палітри одна й
        навмисна: `ремонт` тут окремий аргумент і падає на `зняло_б`, коли його не передали.
        «Що зняло б знахідку» і «що зробити» збігаються не завжди, але там, де збігаються,
        два однакові рядки руками розходяться на наступній правці."""
        зн.append(dict(_РЕЄСТР.зн(правило, сила, суть, [x for x in речі_ if x], чому,
                                  ремонт=ремонт or зняло_б, reg=_РЕЄСТР.REGISTRY, **решта),
                       бік="код", ярлик=ярлик, що_зняло_б=зняло_б,
                       **({"слот": слот} if слот is not None else {})))

    # ── K-COL-02: БЮДЖЕТ ХРОМИ ────────────────────────────────────────────────
    # Метал у ювелірному слоті з бюджету виходить із тієї самої причини, що в
    # `колір_образу.бюджет_хроми`: золотий ланцюжок — не колірний блок. Там межу
    # тримає площа, тут — слот.
    # Гучна річ — `колір_річ.гучність_меж` (КОЛІР-Р4-2б), а не хрома точки: для кольору
    # зі слова точка — центр вікна, і «зелений» (центр C* 52) лічився гучним елементом, хоч виміри
    # того самого слова — C* 22–26. Лічба — «так»; «можливо» лише вирішує, чи стеля «без входу».
    _ел02 = {id(t): _елемент_точки(t, за_ід) for t in точки}
    _бюджетні = [t for t in точки if not (t[1] in ЮВЕЛІРНІ_СЛОТИ and _метал_точки(t, за_ід))]
    гучні_т = [t for t in _бюджетні if гучність_меж(_ел02[id(t)]) == "так"]
    _може02 = [t for t in _бюджетні if гучність_меж(_ел02[id(t)]) == "можливо"]
    гучні = [(t[0], t[1]) for t in гучні_т]
    бюджет = [("«%s»" % (r.get("назва") or r.get("id") or с)) for r, с in гучні]
    особа_гучна, особа_коди = [], []
    # ВОЛОССЯ — ОДИН ЕЛЕМЕНТ (ФОКУС-3). Розкладка кольорів риси дає волоссю кілька
    # голосів (`колір_простір_риси`: «волосся», «волосся_біля_обличчя», моди), і кожен рахувався
    # окремим гучним елементом: на ж6 (fokus_2/ПІСЛЯ) `face: ["hair", "hair"]` робив із туфель і
    # сумки одного тону лічбу 4 при стелі 2. Корпус K-COL-02 «counting hair» — волосся одне.
    # Лише неприродний колір: спільний предикат з добором (`колір_хрома`). Волосся, чийого кольору код не
    # знає (оцінка моделі з портрета), — не «природне», а питання, коли воно вирішило б стелю.
    _голоси = _КХ.голоси_волосся(F)
    _вол = [F[k]["C"] for k, стан in _голоси.items() if стан == "витрачає"]
    _вол_невідоме = not _вол and "невідомо" in _голоси.values()
    if _вол:
        особа_гучна.append("волосся (C*%.0f)" % max(_вол)); особа_коди.append("hair")
    _опр = (F or {}).get("оправа")
    if isinstance(_опр, dict) and _опр.get("C") is None:
        зн.append(_брак_входу("K-COL-02", [dict(річ="оправа")], ("C",)))
    if isinstance(_опр, dict) and _опр.get("C") is not None and _опр["C"] >= гучно:
        особа_гучна.append("оправа (C*%.0f)" % _опр["C"]); особа_коди.append("glasses")
    разом = len(гучні) + len(особа_гучна)
    if разом <= СТЕЛЯ_ГУЧНИХ < разом + len(_може02):
        зн.append(_КО_.без_входу_кольору(
            "K-COL-02", [(_ел02[id(t)],) for t in _може02], перевірка="cannot_tell_chroma_budget_exceeded"))
    # Волосся невідомого кольору — один можливий елемент: питання, лише коли воно вирішило б стелю.
    if _вол_невідоме and разом <= СТЕЛЯ_ГУЧНИХ < разом + len(_може02) + 1:
        зн.append(_брак_входу("K-COL-02", [dict(річ="волосся")], ("C", "h")))
    if разом > СТЕЛЯ_ГУЧНИХ:
        # ВІДЛУННЯ ЛІЧИТЬСЯ ЕЛЕМЕНТАМИ (звірено з корпусом): K-COL-02 рахує «highly
        # saturated elements», а K-COMP-05 велить акцентові стояти у ≥2 точках — пара відлуння
        # якраз і є два елементи при стелі 2. Тому лічба не міняється; міняється ремонт: ЯКИЙ
        # гучний лишити, кажуть `keep`/`quiet` (`_лишити_стишити`), як у K-CRA-02.
        keep, quiet, keep_by = _лишити_стишити(гучні_т, схема_слоти, за_ід)
        _дод("K-COL-02", "strong", "chroma_budget_exceeded",
             "високонасичених елементів %d при стелі 2: %s — решта образу не встигає бути тлом"
             % (разом, ", ".join(бюджет + особа_гучна)),
             "корпус рахує не кольори, а ГУЧНІ елементи, і волосся та оправа входять у "
             "бюджет нарівні з речами: вони теж приобличчевий акцент, тільки постійний",
             _пояснення_без_заміни("K-COL-02"),
             [r.get("id") for r, _ in гучні], поріг=2, вимір=разом,
             заяви=[_ВМ.заява("loud_elements_over_budget", count=разом, ceiling=2,
                              **({"face": особа_коди} if особа_коди else {}),
                              **({"keep": keep, "quiet": quiet, "keep_by": keep_by} if keep else {}))],
             ламається="без виміряних площ дрібний аксесуар важить у лічбі як велика річ — "
                       "поріг ювелірного масштабу тут тримає СЛОТ, а не частка образу")

    # ── K-COL-05: ВІДЛУННЯ ────────────────────────────────────────────────────
    # Групування за дугою (±15° кола художника, КОЛІР-Р2), а не за ім'ям сім'ї, — те саме рішення й з тієї
    # самої причини, що в `колір_образу.відлуння`: сусідні тони (200°, 230°, 255°)
    # читаються як ОДИН акцент, а тверді межі сімей рвали їх на «сироту» й «пару».
    кольорові = [(r, с, L, C, h) for r, с, L, C, h, near in точки
                 if _КР.нейтраль_меж(_елемент_точки((r, с, L, C, h), за_ід)) != "так"
                 and not _метал_точки((r, с, L, C, h), за_ід)]
    # Акцент — певний тон, не темне буре (`колір_образу.акцент_меж`, те саме, що в `колір_образу.відлуння`).
    ел = {id(t): _елемент_точки(t, за_ід) for t in кольорові}
    кольорові = [t for t in кольорові if _КО_.акцент_меж(ел[id(t)]) != "ні"]
    # ── ГРУПУЄТЬСЯ ЛИШЕ ВИМІР ─────────────────────────
    # Тон речі зі слова — центр дуги вікна, а не тон речі: дві «м'ятні» речі мали
    # той самий кут, і «сирота» чи «пара» над ними була наслідком побудови. Тому
    # жадібне групування — те саме, що доти, — іде лише по ВИМІРАХ; речі, чий колір
    # не вимір (`колір_образу.не_вимір`), судяться попарно НА РІВНІ ВІКОН
    # (`відношення`, «same_hue»): «так» — уся дуга в межах дуги відлуння, «ні» — жодна її точка не
    # дістає, інакше «невідомо». Висновок, що стоїть на «невідомо», не робиться ні в
    # той, ні в інший бік: він іде записом «без входу» з названим полем. Образ, у
    # якому всі кольори — виміри, судиться рівно як доти.
    невиміряні = [t for t in кольорові if _КО_.не_вимір(ел[id(t)])]
    _нев = {id(t) for t in невиміряні}
    поруч = lambda a, b: _КО_.відношення(ел[id(a)], ел[id(b)], "same_hue")
    групи = []
    for t in sorted([t for t in кольорові if id(t) not in _нев], key=lambda t: -t[3]):
        for g in групи:
            if поруч(g[0], t) == "так":
                g.append(t); break
        else:
            групи.append([t])
    невідомі = []
    без_кольору = [
        dict(річ=р["id"], слот=р["слот"], колір_тип="невідомо") for р in речі
        if _КР.тип_кольору((за_ід or {}).get(р["id"], р)) == "невідомо"
    ] if повний_склад else ()

    def _сирота(члени, слот, назва, вікна):
        """Знахідка «акцент-сирота» над групою `члени` в одному слоті.

        ОГОЛОШЕНИЙ ФОКУС — НЕ СИРОТА І НЕ ЗНАХІДКА (ФОКУС-1). K-COMP-05: «a
        cobalt bag with nothing cobalt anywhere else fails unless the bag is the declared
        focus». Оголошує фокус схема палітри (акцентний слот, річ несе тон дуги —
        `суд_ремесло.слоти_акценту_схеми`, `схема_слоти`) — один писач оголошеного фокусу:
        фокусної зони сценарію ніхто не пише (Е3-поле-без-писача, 15.11). Доти тут стояла
        знахідка «акцент у оголошеному фокусі» силою hint — похвала без ремонту, а сирота
        над акцентом схеми велів «повторити АБО прибрати», і ремонт прибирав саме акцент
        (розбір 02.10: синя сумка схеми → чорний клатч поруч із K-CRA-02 «лишити сумку»)."""
        if _КХ.акцент_у_оголошеному_фокусі(слот, схема_слоти):   # єдине визначення — його ж читає `колір_хрома`
            return
        можливе_відлуння = [р for р in без_кольору if р["слот"] != слот]
        if можливе_відлуння:
            невідомі.extend((ел[id(члени[0])], р) for р in можливе_відлуння)
            return
        _дод("K-COL-05", "default", "orphan_accent",
             "акцент «%s» стоїть в одному акцентному слоті («%s») і більше ніде — "
             "око не знаходить наміру%s" % (назва, слот, "; на рівні вікон, не виміру"
                                           if вікна else ""),
             "гештальтний повтор: колір, який не відлунює у другій рознесеній зоні і "
             "не оголошений фокусом, читається як шум, а не як хід"
             + ("; колір речі зі слова (центр вікна не судиться), і %s" % вікна
                if вікна else ""),
             _пояснення_без_заміни("K-COL-05"),
             [t[0].get("id") for t in члени], слот=слот, вимір=1, поріг=2,
             заяви=[_ВМ.заява("accent_orphan", colour=_колір_код(назва),
                              hue=round(члени[0][4]) if члени[0][4] is not None else None,
                              slot=сл_код(слот), **({"on_windows": True} if вікна else {}))],
             ламається="без виміряних площ «малість» сироти міряє КЛАС СЛОТА, не частка "
                       "образу: гучна сумка й дрібна брошка тут важать однаково, а "
                       "великий слот із того самого кольору правило мовчки пропускає")

    for g in групи:
        зони = {t[1] for t in g}
        назва = _сім_я_кута(g[0][4]) or "тон ~%d°" % round(g[0][4])
        так = [u for u in невиміряні if поруч(u, g[0]) == "так"]
        може = [u for u in невиміряні if поруч(u, g[0]) == "невідомо"]
        # ВДАЛЕ ВІДЛУННЯ — ОПОРА (ГГ-1; K-COMP-05 «echo for cohesion»). Доти правило
        # говорило лише про ваду (сирота, понад стелю), а відлуння в 2–3 зонах мовчало, і опор на
        # каталозі не було: 0 з 40 випадкових образів, бо єдине відлуння-опора — гучний аксесуар у
        # тон гучної речі (K-ACC-01), а таких пар у пулах сцен стенда нема (`проби/гг_опори_каталог.py`).
        # Відлуння — ТОЙ САМИЙ КОЛІР, а не лише сектор тону: група K-COL-05 тримає й червону сукню
        # (C* 79) з бежево-рожевою сумкою (C* 15), і червону блузу з коричневою сумкою (C* 12) — очима
        # це не повтор акценту. Носій — річ групи напевно без кроку світлоти до акценту (найхроматичнішої,
        # ΔL* < `step_min`) і з хромою, з якої колір читається кольором (`інтерес_c_мін`), як і акцент.
        # Опора — коли такі носії напевно стоять у ≥2 зонах, усі можливі носії групи не понад стелю, і
        # хоч один носій — не велика поверхня (верх + низ одного тону — колона чи костюм, не акцент).
        _колір = lambda t: гучність_меж(ел[id(t)], поріг=_РЕЄСТР.C["інтерес_c_мін"]) == "так"
        носії = [g[0]] + [t for t in g[1:] + так
                          if _колір(t) and _КО_.відношення(ел[id(t)], ел[id(g[0])], "value_step") == "ні"]
        зони_н = {t[1] for t in носії}
        if (_колір(g[0]) and len(зони_н) >= 2
                and len(зони | {u[1] for u in так + може}) <= _РЕЄСТР.C["echo_max"]
                and any(t[1] not in ВЕЛИКІ_СЛОТИ for t in носії)):
            _ід = lambda t: t[0].get("id") or t[0].get("назва") or t[1]
            зн.append(_РЕЄСТР.зн("K-COL-05", "hint",
                "акцент «%s» відлунює у %d зонах — колір тримає образ як намір" % (назва, len(зони_н)),
                [_ід(t) for t in носії],
                "гештальтний повтор: той самий колір у ≥2 рознесених точках читається як хід, а не шум "
                "(K-COMP-05)",
                заяви=[_ВМ.заява("accent_echoed", colour=_колір_код(назва), hue=round(g[0][4]), zones=len(зони_н),
                                 **({"on_windows": True} if any(t in так for t in носії) else {}))],
                полярність=_РЕЄСТР.ОПОРА,
                учасники=[dict(роль="accent", річ=_ід(g[0]))] + [dict(роль="echo", річ=_ід(t)) for t in носії[1:]]))
        if len(зони) == 1:
            слот = next(iter(зони))
            if слот in ВЕЛИКІ_СЛОТИ:
                continue            # велика поверхня — це не сирота-акцент, а сам образ
            if any(u[1] != слот for u in так):
                continue            # відлуння є напевно: уся дуга невиміряної речі в межах дуги відлуння
            if any(u[1] != слот for u in може):
                невідомі += [(ел[id(g[0])], ел[id(u)]) for u in може if u[1] != слот]
                continue
            _сирота(g, слот, назва, "")
            continue
        зони_так = зони | {u[1] for u in так}
        if len(зони_так) > _РЕЄСТР.C["echo_max"]:
            _дод("K-COL-05", "soft", "echo_above_ceiling",
                 "акцент «%s» повторено у %d зонах — повтор перестає читатись як намір і "
                 "стає уніформою%s" % (назва, len(зони_так), "; на рівні вікон, не виміру"
                                      if так else ""),
                 "стеля відлуння: 4+ носії одного кольору — це вже matchy, а не перегук"
                 + ("; на рівні вікон: %d із них — речі зі слова, чия дуга вся в межах 45°"
                    % len(так) if так else ""),
                 "лишити 2–3 носії, решту перевести в нейтраль",
                 [t[0].get("id") for t in g + так], вимір=len(зони_так),
                 поріг=_РЕЄСТР.C["echo_max"],
                 заяви=[_ВМ.заява("accent_echo_over_ceiling", colour=_колір_код(назва), hue=round(g[0][4]),
                                  zones=len(зони_так), ceiling=_РЕЄСТР.C["echo_max"],
                                  **({"on_windows": True} if так else {}))],
                 ремонт_заяви=[_ВМ.заява("keep_two_three_carriers")],
                 ламається="тональна колона одного кольору — інша схема (K-COL-03 §2), не "
                           "відлуння; схема образу сюди не доїжджає, тому стеля тут груба")
        elif len(зони_так | {u[1] for u in може}) > _РЕЄСТР.C["echo_max"]:
            невідомі += [(ел[id(g[0])], ел[id(u)]) for u in може]
    # Невиміряний акцент сам: сирота лише тоді, коли тон жодної іншої речі не
    # дістає дуги відлуння на всьому його вікні; відлуння — коли хоч одна дістає цілою дугою.
    for u in невиміряні:
        if u[1] in ВЕЛИКІ_СЛОТИ:
            continue
        стани = [(t, поруч(u, t)) for t in кольорові if t is not u and t[1] != u[1]]
        if any(в == "так" for _, в in стани):
            continue
        if all(в == "ні" for _, в in стани):
            _сирота([u], u[1], (_КО_.не_вимір(ел[id(u)]) or {}).get("слово")
                    or _КР.сім_я_меж(ел[id(u)]) or "невідомий тон",
                    "тон жодної іншої кольорової речі не дістає ±15° кола художника на всьому вікні"
                    if стани else "інших кольорових речей в образі нема — відлунювати нема чому")
            continue
        невідомі += [(ел[id(u)], ел[id(t)]) for t, в in стани if в == "невідомо"]
    if невідомі:
        зн.append(_КО_.без_входу_кольору(
            "K-COL-05", невідомі, перевірка="cannot_tell_accent_echoed"))
    return зн

def _елемент_точки(t, за_ід=None):
    """Точка `_кольори_образу` (річ, слот, L, C, h, …) → елемент для помічників
    `колір_образу`: lab, провенанс кольору (`колір_не_вимір` із запису
    КАТАЛОГУ — рядок пулу його не несе), id, назва, слот."""
    r = t[0]
    повна = (за_ід or {}).get(r.get("id")) or r
    return dict(lab=_КР.точка_кольору(повна), колір_тип=_КР.тип_кольору(повна),
                колір_не_вимір=_КР.не_вимір(повна),
                річ=r.get("id"), назва=повна.get("назва") or r.get("назва"), слот=t[1],
                тип=повна.get("тип") or r.get("тип"))

def _метал_точки(t, за_ід=None):
    """Чи колір запису є металом: код матеріалу в слоті фурнітури без вставки (`palettes.колір_металу`, 14314)."""
    r = t[0]
    повна = (за_ід or {}).get(r.get("id")) or r
    повна = dict(повна, слот=t[1], тип=повна.get("тип") or r.get("тип"))
    if _КР.межі_кольору(повна) is None:
        return False
    return _ПЛ.колір_металу(повна)

def акцент_образу(речі, спец_слоти, кандидати=None, за_ід=None, *, прогін_руки=None):
    """[знахідки] — де роль «акцент» призначена, але хроми в образі нема.

    `за_ід` — id → запис КАТАЛОГУ. Він тут обов'язковий: записи пулу, які їдуть
    до моделі, несуть лише назву, ціну й словесну зону, БЕЗ `lab`. Рахувати
    хрому по них означало б діставати None на кожній речі й через це завжди
    списувати провал на каталог — тобто зробити звинувачення сталим, а перевірку
    невідрізненною від заглушки. Спіймано першим же прогоном: «у пулі НЕМА
    жодної речі з хромою» стояло і там, де речі були.
    """
    if not спец_слоти:
        return []
    за_слотом = {}
    for r in речі:
        за_слотом.setdefault(r.get("слот"), r)
    def _акцент(сила, с, суть, чому, бік, ярлик, що_зняло_б, **решта):
        """Знахідка K-PAL-18 акцентного слота: конструктор і поля суду одним викликом (як `_дод`
        прийомів палітри); `решта` — `заяви`, `ремонт_заяви` конструктора."""
        return dict(_РЕЄСТР.зн("K-PAL-18", сила, суть, [], чому, reg=_РЕЄСТР.REGISTRY, **решта),
                    бік=бік, слот=с, ярлик=ярлик, що_зняло_б=що_зняло_б)

    зн = []
    # ключі на «_» — службові (напр. `_схема`), не слоти. Без цього фільтра
    # рядок схеми потрапляв у цикл як «слот» і валив перевірку AttributeError.
    # СХЕМА ВЕЛИКИХ ПОВЕРХОНЬ: сім'ї схеми вільно лягають на будь-яку велику
    # річ (сім'я-верх може стояти і на жакеті), тож «акцент саме в цьому слоті» тут хибна
    # вимога: на дощовому образі вона казала «акцент на жакеті», поки K-COL-03 казав
    # «заміни верх» — дві знахідки, що суперечать одна одній. Схему цілком судить K-COL-03
    # (`palette.обіцянка_великих`), покомпонентний акцент мовчить.
    if спец_слоти.get("_поверхні") == "великі":
        return []
    # траурна нагода зі схемою коду: акцентна роль тут не проситься
    if спец_слоти.get("_траур"):
        return []
    # служба в церкві, схему обрала не вона (СХЕМА-КАРТКА): образ без кольору доречний,
    # тож низька хрома акцентного слота — не знахідка; той самий предикат, що в `обіцянка_схеми`
    if спец_слоти.get("_нагода_без_акценту"):
        if not any(_ПЛ.несе_колір((за_ід or {}).get(r.get("id")) or r) for r in (речі or [])):
            return []
    акцентні = [(с, сп) for с, сп in спец_слоти.items()
                if not str(с).startswith("_") and isinstance(сп, dict)
                and сп.get("роль") == "акцент" and сп.get("C")]
    for с, сп in акцентні:
        r = за_слотом.get(с)
        if r is None:                      # слота в образі нема — це не «зник акцент»
            continue
        # Хрома проти стелі ролі — `колір_річ.гучність_меж` з порогом ролі (КОЛІР-Р4-2б):
        # доти `_хрома` брала C* точки, і річ-вікно слова судилась центром вікна. «так» — роль
        # тримає вся хрома вікна (вимір — як доти); «можливо» — «без входу»; «ні» — уся хрома нижче.
        Cmin = float(сп["C"][0])
        _г = гучність_меж(r, поріг=Cmin)
        if _г is None:                     # кольору нема: мовчати чесніше,
            continue                       # ніж рахувати невимір за провал
        if _г == "так":
            зн = _ПОЛ.злам("K-PAL-18", "акцент", зн, r=r, слот=с, Cmin=Cmin, прогін_руки=прогін_руки)
            continue
        if _г == "можливо":
            зн.append(_КР.без_входу_кольору(
                "K-PAL-18", [(r,)], перевірка="cannot_tell_accent_role_chroma"))
            continue
        C = _КР.межі_кольору(r)[3]       # «ні»: уся хрома під порогом — у текст верхня межа
        # чи взагалі БУЛО з чого взяти акцент у цьому слоті
        пул = ((кандидати or {}).get(с) or [])
        повні = [(за_ід or {}).get(x.get("id")) or x for x in пул]
        мали = [x for x in повні if гучність_меж(x, поріг=Cmin) == "так"]
        if мали:
            зн.append(_акцент(
                "soft", с,
                ("схема «%s» дала слоту «%s» роль акценту (хрома від %.0f), "
                 "а річ у ньому має %.0f — у пулі було %d речей із хромою"
                 % (спец_слоти.get("_схема", "?"), с, Cmin, C, len(мали))),
                "вибір проти власної спеки: акцент був доступний і не взятий", "код", "accent_absent",
                заяви=[_ВМ.заява("accent_role_lost", scheme=_схема_код(спец_слоти.get("_схема")),
                                 slot=сл_код(с), chroma_from=round(Cmin), chroma=round(C),
                                 pool_count=len(мали))],
                що_зняло_б=_пояснення_без_заміни("K-PAL-18")))
        else:
            зн.append(_акцент(
                "hint", с,
                ("схема «%s» вимагає акценту в слоті «%s» (хрома від %.0f), "
                 "але в пулі цього слота НЕМА жодної речі з такою хромою"
                 % (спец_слоти.get("_схема", "?"), с, Cmin)),
                "дефіцит каталогу, не вибір моделі: звинувачувати модель тут — помилка атрибуції",
                "дані", "accent_pool_empty",
                заяви=[_ВМ.заява("accent_role_none_in_pool", scheme=_схема_код(спец_слоти.get("_схема")),
                                 slot=сл_код(с), chroma_from=round(Cmin))],
                ремонт_заяви=[_ВМ.заява("not_fixable_from_pool")],
                що_зняло_б="джерела з кольоровими речами в цьому слоті"))
    # ЗВЕДЕНОЇ ЗНАХІДКИ («жоден акцентний слот не несе хроми») ТУТ НЕМА НАВМИСНО.
    # Вона була написана й ВИДАЛЕНА того ж прогону: `слот=None` не чіпляється до
    # жодної речі, тому граф її відкидає, і назовні їхали дві знахідки з трьох.
    # Правило, яке виконується, лишає слід і не доходить до людини, — рівно той
    # третій ярус, який тут заборонено. Дві послотові знахідки кажуть усе те саме
    # й доїжджають.
    return _ПОЛ.злам("K-PAL-18", "справні", зн, прогін_руки=прогін_руки)
