def код_назви(назва):
    """Код, закріплений за назвою (слово словника або вирішена назва), або None."""
    return КОД_НАЗВИ.get(str(назва or "").strip(" ,.").casefold())


def розбіжності_назв(пари):
    """{назва: {код, …}} для пар (назва, код), де назва має закріплений код, а відповідь дала інший;
    ще й назви без закріпленого коду, що в тих самих парах дістали різні коди (спірні — без рішення)."""
    інший, вільні = {}, {}
    for назва, код in пари:
        н = str(назва or "").strip(" ,.").casefold()
        закріплений = КОД_НАЗВИ.get(н)
        if закріплений is None:
            вільні.setdefault(н, set()).add(код)
        elif код != закріплений:
            інший.setdefault(н, set()).add(код)
    return інший, {н: к for н, к in вільні.items() if len(к) > 1}
