class Купівля_РічВаріант(unittest.TestCase):
    """Функція «купити річ» (#4689, смуга «Функції»): порада пошуку прив'язана до конкретного знайденого варіанта, а
    однойменні товари їй розрізняє лише видиме місце в переліку («Варіант N» на картці) — те саме число доходить до
    неї в тексті перекладача, вигадане — ні. Вхід — справжній пошук на записаному стенді (дві «Куртка джинсова
    жіноча» в `каталог_brief.xml`); репліку складено так, як її складає показ (`показ/інструменти.js`, find_item)."""
    _пошук = None

    @classmethod
    def пошук(cls):
        if cls._пошук is None:
            cls._пошук = виклик("пошук_речі", dict(_Стенд.дати()["вх"], опис={"item_type": "jacket"}))
        return cls._пошук

    @staticmethod
    def репліка(р):
        return {"item_verdicts": [dict({"item_id": в["ід"], "catalogue_position": н + 1, "slot": в["slot"],
                                        "item_type": в["item_type"], "verdict": в["вердикт"]["повідомлення"]},
                                       **({"item": {"free_text": в["назва"], "lang": "uk"}} if в.get("назва") else {}))
                                  for н, в in enumerate(р["варіанти"])] + [{"verdict": р["повідомлення"]}]}

    def test_порада_пошуку_називає_лише_знайдені_варіанти(self):
        р = self.пошук()
        ід = [в["ід"] for в in р["варіанти"]]
        self.assertGreaterEqual(len(ід), 2, "записаний пошук не дав вибору")
        self.assertTrue(р["choice"], "між кількома варіантами нема заяви вибору")
        for з in р["choice"]:
            названі = list(з.get("item_ids") or ()) + list((з.get("values") or {}).get("then") or ()) \
                + list((з.get("values") or {}).get("proven_over") or {})
            self.assertTrue(названі and set(названі) <= set(ід), "заява %s називає не знайдений варіант" % з["code"])
            self.assertEqual([і for і in ід if і in (з.get("item_ids") or ())], list(з.get("item_ids") or ()),
                             "порядок заяви %s не той, що в переліку" % з["code"])

    def test_ід_крамниці_до_моделі_не_доходить(self):
        # 17104: тіло запиту купівлі несло ід із доменом крамниці (56 входжень у живому запиті) — `then`, ключі
        # `proven_over`, `item_ids` заяв. Межа ставить номер речі за значенням, а не за назвою поля.
        р = self.пошук()
