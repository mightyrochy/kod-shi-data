class _Стенд:
    """Один паспорт і один запит на весь модуль: запит — ~8 с, решта викликів — частки секунди."""
    _готово = None

    @classmethod
    def дати(cls):
        if cls._готово is None:
            тека = tempfile.mkdtemp(prefix="інваріанти_")
            кеш = os.path.join(тека, "кеш_кольорів.json")
            with open(кеш, "w", encoding="utf-8") as ф:
                json.dump({}, ф)
            with open("стенд_вх.json", encoding="utf-8") as ф:
                вх = json.load(ф)
            вх["каталог"] = feed.каталог_на_диску(КАТАЛОГ)
            вх["кеш_кольорів"] = кеш
            вх["сценарій"] = {}
            паспорт = виклик("паспорт", {"json_моделі": json.dumps(ВІДПОВІДЬ_МОВНОЇ_МОДЕЛІ, ensure_ascii=False),
                                          "сценарій": {}, "вимоги": ЇЇ_СЛОВА})["паспорт"]
            вх["паспорт"] = паспорт
            запити = виклик("запити", dict(вх, пакети=1))
            cls._готово = {"вх": вх, "паспорт": паспорт, "запити": запити,
                           "руки": {р: json.loads(т) for р, т in запити["руки"].items()},
                           "пул": запити["пакети"]["1"]["пул"]}
        return cls._готово


def рядки_з_шляхами(о, шлях=""):
    """Усі рядки й ключі об'єкта з їхнім шляхом — щоб сказати, ДЕ саме в запиті стоїть слово."""
    if isinstance(о, dict):
        for к, в in о.items():
            yield шлях + "/" + str(к), str(к)
            yield from рядки_з_шляхами(в, шлях + "/" + str(к))
    elif isinstance(о, list):
        for і, в in enumerate(о):
            yield from рядки_з_шляхами(в, "%s[%d]" % (шлях, і))
    elif isinstance(о, str):
        yield шлях, о


