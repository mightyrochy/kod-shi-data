class Е2_СмугаПогодиЙЧастинаДня(unittest.TestCase):
    """Корені Е2-смуга-погоди й Е2-частина-дня: коду — смуга погоди й частина дня, а не градуси й година."""

    ЇЇ_ТЕКСТ = ("/her_words", "/слова", "/вимоги")  # її власні слова — цитата цілком, не поле коду

    def test_стилістка_дістає_смугу_й_частину_дня(self):
        с = _Стенд.дати()
        for рука, п in с["руки"].items():
            with self.subTest(рука=рука):
                день = п.get("day") or п["case"]  # руки 3–4 несуть день у `case`
                self.assertEqual(день.get("weather_band"), "cold", "смуга погоди не дійшла до руки %s" % рука)
                self.assertEqual(день.get("part_of_day"), "evening", "частина дня не дійшла до руки %s" % рука)

    def test_градуси_й_година_не_доходять_полем(self):
        с = _Стенд.дати()
        ключ_числа = re.compile(r"temperat|temp_c|\bhour|wind(?!ow)|градус|годин|темп_|вітер", re.IGNORECASE)
        число = re.compile(r"°|\b19:00\b|м/с|\bm/s\b")
        for де, о in [("паспорт", с["паспорт"])] + [("рука " + р, п) for р, п in с["руки"].items()]:
            for шлях, рядок in рядки_з_шляхами(о):
                if шлях.endswith(self.ЇЇ_ТЕКСТ):
                    continue
                with self.subTest(де=де, шлях=шлях):
                    if шлях.rsplit("/", 1)[-1] == рядок:
                        self.assertIsNone(ключ_числа.search(рядок), "поле градусів чи години в %s: %s" % (де, шлях))
                    else:
                        self.assertIsNone(число.search(рядок), "градуси чи година в %s: %s = %r" % (де, шлях, рядок[:120]))


