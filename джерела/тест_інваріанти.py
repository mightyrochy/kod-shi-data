def _вузли(о):
    """Усі вкладені значення об'єкта (dict і list) — щоб знайти вузол запиту за його полями, а не за шляхом."""
    yield None, о
    if isinstance(о, dict):
        for в in о.values():
            yield from _вузли(в)
    elif isinstance(о, list):
        for в in о:
            yield from _вузли(в)


