    """Корінь Е2-втрата-слова: її слово доходить до стилістки, а не взяте кодом видно як не взяте."""

    def test_слово_з_розмови_дійшло_до_запиту_стилістці(self):
        с = _Стенд.дати()
        self.assertEqual(sorted(с["руки"]), ["1", "2", "3", "4"])
        for рука, п in с["руки"].items():
            with self.subTest(рука=рука):
                self.assertIn(ЇЇ_БАЖАННЯ, п["case"].get("wishes") or [], "її бажання не дійшло до руки %s" % рука)
