        ід = [в["ід"] for в in р["варіанти"]]
        домени = {і.rpartition("@")[2] for і in ід if "@" in і}
        self.assertEqual([і for і in ід if і in промпт] + [д for д in домени if д in промпт], [],
                         "ід крамниці дійшов до моделі")
        факти = _факти_промпту(промпт)
        речі = [н for н, ф in факти.items() if ф["state"] == "item"]
