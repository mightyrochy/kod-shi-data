"""КЕШ ЗА ВХОДОМ для чистих важких функцій ядра (крок 1.1-А, корінь К-7 «швидкодія»).

ЩО ЦЕ МІНЯЄ В РІШЕННІ. `від_моделі` на кожну відповідь моделі заново будував той самий бриф
(`brief.бриф` → двічі `hypergraph.простір`): на записаному прогоні — 50 викликів `бриф` на 3 різні
входи й 105 викликів `простір` на 2, і всі повтори віддавали вихід, байт у байт рівний першому.
Тепер повтор із тим самим входом бере готовий вихід. Гіперграф при цьому не перебудовується (п.17).

ЩО В КЛЮЧІ. Кеш не має права віддати чужий вихід, тому ключ — усе, від чого вихід залежить:
  · аргументи (`repr`: порядок ключів у dict — вхід, а не шум, зате без обходу структури у Python —
    пакет брифа важить 425 КБ, `repr` коштує кілька мс, обхід — десятки);
  · стан руки 2 (`правило_руки2`: вимкнені, зламані, стежені) — `вимкнене`/`зламане` читають його
    глибоко в `fit` і `силует`, і `простір` під зламаним K-FIT-03 дає інший вихід, ніж без нього;
  · чи увімкнено слід (`trace`).
ЩО ЛИШАЄТЬСЯ ПОЗА КЛЮЧЕМ ЗА ПОБУДОВОЮ: константи модулів (їх не міняє нічого, окрім правки коду).

ПОБІЧНІ ЕФЕКТИ. Функція пише слід (`trace.запис`): повтор без запису змінив би `слід_правил` у виході моста.
Тому разом з виходом кеш тримає записи, які додав перший виклик, і на попаданні дописує їх. Запис у тінь
руки 2 кеш не повторює: виклик, що писав у тінь, не кешується взагалі.

ВИХІД НІКОМУ НЕ ЧУЖИЙ. Читачі міняють вихід (`brief.перекинути_метал` переписує рядок правила руки 2), тож
кеш тримає власну копію й віддає копію.

ЦІНА НАЗВАНА. Інший порядок ключів у dict чи інший порядок елементів множини — інший ключ, тобто
зайвий промах (повна побудова), а не хибне влучання. Розмір — `ємність` записів, найдавніший іде геть."""
import copy
import functools
import hashlib
import inspect
from collections import OrderedDict

import trace as СЛ
import правило_руки2 as ПР2

_УСІ = []     # лічильники всіх кешів — для проб і `скинути`


def _стан_руки_2(вимкнені=None, зламані=None):
    """Те, що `вимкнене`/`зламане` читають із контексту руки 2 для цієї функції, відсортованим.

    `стежені` не міняють ні виходу, ні `trace.запис`: коли стежене правило спрацьовує, воно пише
    в `ПР2.тінь()`, і такий виклик нижче все одно не кешується (`len(ПР2.тінь()) != тінь`).
    Якщо функція залежить лише від підмножини правил (`вимкнені`/`зламані`), решта кодів у
    контексті руки 2 її виходу не змінює й ключ кеша не розщеплює (крок 1.1-Б)."""
    в = ПР2.вимкнені() if вимкнені is None else (ПР2.вимкнені() & вимкнені)
    з = ПР2.зламані() if зламані is None else (ПР2.зламані() & зламані)
    return (tuple(sorted(в)), tuple(sorted(з)))


def за_входом(ємність, *, вимкнені=None, зламані=None, нормалізувати=None):
    """Декоратор: повтор виклику з тим самим входом і станом руки 2 віддає копію готового виходу."""
    ф_вимк = None if вимкнені is None else frozenset(вимкнені)
    ф_злам = None if зламані is None else frozenset(зламані)

    def декоратор(ф):
        сховище = OrderedDict()
        лічильник = dict(виклики=0, промахи=0, не_кешовано=0)
        сигн = inspect.signature(ф)

        @functools.wraps(ф)
        def обгортка(*арг, **кварг):
            лічильник["виклики"] += 1
            зв = сигн.bind_partial(*арг, **кварг)
            зв.apply_defaults()
            if нормалізувати is not None:
                нормалізувати(зв.arguments)
            ключ = hashlib.sha256(repr((tuple(зв.arguments.items()),
                                        _стан_руки_2(ф_вимк, ф_злам),
                                        СЛ.увімкнено())).encode("utf-8", "surrogatepass")).digest()
            if ключ in сховище:
                сховище.move_to_end(ключ)
                вихід, записи, записи_тіні = сховище[ключ]
                СЛ.повторити(записи)
                for _т in записи_тіні:
                    ПР2.в_тінь(**copy.deepcopy(_т))
                return copy.deepcopy(вихід)
            лічильник["промахи"] += 1
            позначка, тінь = СЛ.позначка(), len(ПР2.тінь())
            вихід = ф(*арг, **кварг)
            нові_тіні = ПР2.тінь()[тінь:]
            if нові_тіні and ПР2.стежені():
                лічильник["не_кешовано"] += 1
                return вихід
            сховище[ключ] = (copy.deepcopy(вихід), СЛ.записи_після(позначка),
                             copy.deepcopy(нові_тіні))
            while len(сховище) > ємність:
                сховище.popitem(last=False)
            return вихід

        обгортка.лічильник = лічильник
        обгортка.скинути = сховище.clear
        _УСІ.append(обгортка)
        return обгортка
    return декоратор


def скинути():
    """Спорожнити всі кеші й лічильники (проби, що міряють «до/після» в одному процесі)."""
    for о in _УСІ:
        о.скинути()
        о.лічильник.update(виклики=0, промахи=0, не_кешовано=0)
