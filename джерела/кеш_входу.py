"""КЕШ ЗА ВХОДОМ для чистих важких функцій ядра (крок 1.1-А, корінь К-7 «швидкодія»).

ЩО ЦЕ МІНЯЄ В РІШЕННІ. `від_моделі` на кожну відповідь моделі заново будував той самий бриф
(`brief.бриф` → двічі `hypergraph.простір`): на записаному прогоні — 50 викликів `бриф` на 3 різні
входи й 105 викликів `простір` на 2, і всі повтори віддавали вихід, байт у байт рівний першому.
Тепер повтор із тим самим входом бере готовий вихід. Гіперграф при цьому не перебудовується (п.17).

ЩО В КЛЮЧІ. Кеш не має права віддати чужий вихід, тому ключ — усе, від чого вихід залежить:
  · аргументи (`repr`: порядок ключів у dict — вхід, а не шум, зате без обходу структури у Python —
    пакет брифа важить 425 КБ, `repr` коштує кілька мс, обхід — десятки);
  · зламані правила прогону (`поломки.зламані`) — точки зламу стоять глибоко в `fit` і `силует`, і
    `простір` під зламаним K-SIL-03 дає інший вихід, ніж без нього;
  · стежені правила — лише коли побудова про них питала (див. нижче);
  · чи увімкнено слід (`trace`).
ЩО ЛИШАЄТЬСЯ ПОЗА КЛЮЧЕМ ЗА ПОБУДОВОЮ: константи модулів (їх не міняє нічого, окрім правки коду).

СТЕЖЕНІ — У КЛЮЧІ ЛИШЕ ТАМ, ДЕ ПОБУДОВА ПРО НИХ ПИТАЛА (крок 1.1-Б). Стеження (`поломки.стежити_за`) нічого не міняє у виході
функції: `свідок` і `відсіяти` лише дописують дію правила в тінь. Але дописують, коли правило серед стежених, — тож вихід,
взятий з кешу, мусив би дописати те саме. Тому читання стежених лічиться у переданому об’єкті прогону: побудова, яка за
стеженими не питала жодного разу (і її внутрішні кешовані виклики теж), не залежить від них за побудовою і лягає під
ключ БЕЗ них — повтор за іншого набору стежених береться з кешу. Та, що питала, лягає під повний ключ, як і досі.
Влучання в запис, який питав, теж лічиться питанням — для зовнішньої побудови, що викликала цей кеш.

ПОБІЧНІ ЕФЕКТИ. Функція пише слід (`trace.запис`): повтор без запису змінив би `слід_правил` у виході моста.
Тому разом з виходом кеш тримає записи, які додав перший виклик, і на попаданні дописує їх. Запис у тінь
руки 2 кеш не повторює: виклик, що писав у тінь, не кешується взагалі.

ВИХІД НІКОМУ НЕ ЧУЖИЙ. Читачі можуть міняти вихід (доти `brief.перекинути_метал` переписував рядок правила руки 2), тож
кеш тримає власну копію й віддає копію. Копія — `_копія`, а не `copy.deepcopy`: вихід — звичайні dict/list/tuple із
рядків і чисел (пакет `_пакет` — 430 КБ, 40 тис. словників), і `deepcopy` на кожному листку кличе функцію; `_копія` листки
не кличе (у Pyodide це чверть часу `від_моделі` після кешу) й зберігає спільні посилання так само, як `deepcopy`.

ЦІНА НАЗВАНА. Інший порядок ключів у dict чи інший порядок елементів множини — інший ключ, тобто
зайвий промах (повна побудова), а не хибне влучання. Розмір — `ємність` записів, найдавніший іде геть."""
import copy
import functools
import hashlib
from collections import OrderedDict

import trace as СЛ
import поломки_ядро as _ПОЛ

_УСІ = []     # лічильники всіх кешів — для проб і `скинути`
_ЛИСТКИ = frozenset((type(None), bool, int, float, str, bytes))


def _копія(о, пам=None):
    """Глибока копія, рівна `copy.deepcopy` (спільні посилання лишаються спільними), але без виклику на кожному листку;
    тип, якого тут нема (множина, клас), копіює `deepcopy` з тією самою пам'яттю."""
    пам = {} if пам is None else пам
    т = type(о)
    if т in _ЛИСТКИ:
        return о
    і = id(о)
    if і in пам:
        return пам[і]
    if т is dict:
        н = пам[і] = {}
        for к, з in о.items():
            н[к if type(к) in _ЛИСТКИ else _копія(к, пам)] = з if type(з) in _ЛИСТКИ else _копія(з, пам)
        return н
    if т is list:
        н = пам[і] = []
        for з in о:
            н.append(з if type(з) in _ЛИСТКИ else _копія(з, пам))
        return н
    if т is tuple:
        н = tuple(з if type(з) in _ЛИСТКИ else _копія(з, пам) for з in о)
        пам[і] = о if all(a is b for a, b in zip(н, о)) else н
        return пам[і]
    return copy.deepcopy(о, пам)


def _стан_руки_2(прогін_руки):
    """Зламані правила прогону, відсортованими: вони міняють вихід завжди."""
    return tuple(sorted(_ПОЛ.зламані(прогін_руки=прогін_руки)))


def _стежені(прогін_руки):
    """Стежені правила, відсортованими; читання не лічиться (це ключ, а не рішення правила)."""
    return tuple(sorted(_ПОЛ.стан_стежених(прогін_руки=прогін_руки)))


def за_входом(ємність):
    """Декоратор: повтор виклику з тим самим входом і станом руки 2 віддає копію готового виходу."""
    def декоратор(ф):
        сховище = OrderedDict()
        лічильник = dict(виклики=0, промахи=0, не_кешовано=0)

        @functools.wraps(ф)
        def обгортка(*арг, **кварг):
            прогін_руки = кварг.get("прогін_руки")
            лічильник["виклики"] += 1
            основа = repr((арг, sorted((к, в) for к, в in кварг.items() if к != "прогін_руки"), _стан_руки_2(прогін_руки), СЛ.увімкнено()))
            вузький = hashlib.sha256(основа.encode("utf-8", "surrogatepass")).digest()
            повний = hashlib.sha256((основа + repr(_стежені(прогін_руки))).encode("utf-8", "surrogatepass")).digest()
            for ключ in (вузький, повний):
                if ключ in сховище:
                    сховище.move_to_end(ключ)
                    вихід, записи, питав = сховище[ключ]
                    if питав:
                        _ПОЛ.стан(прогін_руки).питали_стежені += 1
                    СЛ.повторити(записи)
                    return _копія(вихід)
            лічильник["промахи"] += 1
            позначка, тінь, питали = СЛ.позначка(), len(_ПОЛ.тінь(прогін_руки=прогін_руки)), _ПОЛ.стан(прогін_руки).питали_стежені
            вихід = ф(*арг, **кварг)
            if len(_ПОЛ.тінь(прогін_руки=прогін_руки)) != тінь:
                лічильник["не_кешовано"] += 1
                return вихід
            питав = _ПОЛ.стан(прогін_руки).питали_стежені != питали
            сховище[повний if питав else вузький] = (_копія(вихід), СЛ.записи_після(позначка), питав)
            while len(сховище) > ємність:
                сховище.popitem(last=False)
            return вихід

        обгортка.лічильник = лічильник
        обгортка.скинути = сховище.clear
        _УСІ.append(обгортка)
        return обгортка
    return декоратор


def скинути():
    """Спорожнити всі кеші й лічильники (проби, що міряють «до/після» в одному процесі)."""
    for о in _УСІ:
        о.скинути()
        о.лічильник.update(виклики=0, промахи=0, не_кешовано=0)
