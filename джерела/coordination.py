def координація(E, набір_кандидатів=None, метрика="oklab", зважувати_площею=False, зсув_вершини=None):
    """K-COMP-01. Одна знахідка: де цей образ стоїть на кривій координації.

    `набір_кандидатів` — список середніх близькостей ІНШИХ кандидатів для цієї самої
    людини й нагоди. Без нього рангу не існує, і правило утримується: абсолютного
    порогу в статті нема, і вигадувати його заборонено."""
    моя = середня_близькість(E, зважувати_площею, метрика)
    речі = [e["річ"] for e in кольоронесучі(E)]
    if моя is None:
        return [dict(правило="K-COMP-01", сила="утримано", сила_нп=None,
                     сила_нп_джерело="виміру нема (утримано): менше двох кольоронесучих слотів",
                     суть="координація не рахується", речі=речі,
                     чому="кольоронесучих речей %d при мінімумі %d — попарної "
                          "близькості не існує" % (len(речі), C["мін_слотів"]),
                     ремонт="додати другу кольоронесучу річ або нічого не стверджувати")]
    if not набір_кандидатів:
        return [dict(правило="K-COMP-01", сила="утримано", сила_нп=None,
                     сила_нп_джерело="виміру нема (утримано): набору кандидатів не передано",
                     суть="середня попарна близькість %.1f ΔE00 порахована, ранг — ні" % моя,
                     речі=речі,
                     чому="оптимум у Gray та ін. 2014 — це ПОЗИЦІЯ В НАБОРІ (z-скор "
                          "усередині палітри), а не абсолютна колірна відстань. Без "
                          "набору кандидатів судити нема від чого, а вигадувати "
                          "абсолютну смугу ΔE прямо заборонено джерелом",
                     ремонт="передати середні близькості інших кандидатів для цієї "
                            "людини й нагоди (feed.покриття дає пул)")]
    діагноз = розкид_набору(list(набір_кандидатів) + [моя], метрика)
    if not діагноз["можна"]:
        return [dict(правило="K-COMP-01", сила="утримано", сила_нп=None,
                     сила_нп_джерело="виміру нема (утримано): набір без розкиду",
                     суть="ранг не рахується — набір кандидатів колірно однорідний",
                     речі=речі, чому=діагноз["чому"], розкид_набору=діагноз,
                     ремонт="розширити ретрив: узяти кандидатів з іншими колірними "
                            "сім'ями, інакше колірний шар тут не має роздільної здатності")]
    ранг = ранг_у_наборі(моя, list(набір_кандидатів) + [моя])
    оц = оцінка_координації(ранг, зсув_вершини)
    бік = ("надкоординація (matchy): образ скоординованіший за більшість набору"
           if ранг < 0.5 else
           "розлад: образ розбіжніший за більшість набору")
    return [dict(O._зн(
        # ЗНАЙДЕНО ПЕРЕВІРКОЮ КОДУ ПРОТИ КОРПУСУ: цей виклик ішов БЕЗ `reg` і БЕЗ
        # `рег_карта`, тобто стеля тіру рахувалась по outfit.REGISTRY, який про
        # K-COMP-01 нічого не знає -> None -> інваріант «сила ≤ верифікація» тут не
        # працював зовсім, попри те, що докстрінг файлу його заявляє. Локальний
        # РЕГІСТР_ПРАВИЛА при цьому був мертвим кодом: він збігався з дефолтом
        # випадково. Тепер обидва передані, і машинерія одна на всі модулі правил.
        "K-COMP-01", "default" if оц is not None and оц < 0.5 else "hint",
        "позиція на кривій координації: %.2f від оптимуму" % (1.0 - (оц or 0.0)),
        речі,
        "середня попарна близькість %.1f ΔE00 → ранг %.2f у наборі з %d кандидатів "
        "(розкид набору %.1f ΔE00, σ %.1f); оптимум на ранзі %.2f; %s"
        % (моя, ранг, діагноз["n"], діагноз["розкид"], діагноз["σ"],
           min(0.95, max(0.05, 0.5 + (C["зсув_вершини"] if зсув_вершини is None
                                      else зсув_вершини))), бік),
        ремонт=("узяти кандидата з БІЛЬШОЮ колірною відстанню між слотами "
                "(інша сім'я в одному зі слотів)" if ранг < 0.5 else
                "узяти кандидата з МЕНШОЮ колірною відстанню (звести один слот у "
                "нейтраль або в сім'ю іншого)"),
        запит=dict(слот="будь-який кольоронесучий",
                   цільова_середня_ΔE00="ранг ≈ 0.5 у ЦЬОМУ наборі, не абсолютне число",
                   чому="K-COMP-01: помірна координація, нормалізована по набору"),
        вимір=abs((ранг or 0.5) - 0.5), поріг=0.0, повна=0.5,
        ламається="ΔE00 підставлений замість людських оцінок «coordinated/matching/"
                  "similar» — це наша заміна, не результат Gray. Плюс обмеження самої "
                  "статті: 4-кольорові палітри, ілюстровані стимули, n=60 на рівні "
                  "підігнаної кривої, зовнішня валідність автори називають "
                  "неперевіреною, і вони ПРЯМО не стверджують, що помірний збіг — "
                  "домінантний чинник. Стеля всього шару 44% дисперсії, і то лише "
                  "коли решта зафіксована",
        reg=РЕЄСТР, рег_карта=РЕГІСТР_ПРАВИЛА),
        сила_нп=round(1.0 - (оц or 0.0), 2),
        сила_нп_джерело="вимір (власний: відстань рангу від вершини)",
        ранг=ранг, оцінка=оц, середня_ΔE00=моя, розкид_набору=діагноз)]


