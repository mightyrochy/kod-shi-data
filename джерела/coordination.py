def пари_близькості(E, зважувати_площею=False, метрика="oklab"):
    """Усі k(k−1)/2 попарних перцептивних близькостей між кольоронесучими слотами.

    `зважувати_площею` — НАША добудова, не з Gray. Кожне одягове джерело трактує
    частку площі як обов'язкову ознаку (Li та ін. 2025 подають її явно серед 20
    ознак; правило площі Munsell будує на ній усе), а Gray площею не керував узагалі:
    у нього чотири кольори на чотири слоти рівних ваг. Тому зважування вимкнене за
    замовчуванням — увімкнене воно відповідає на ІНШЕ питання, ніж те, що виміряне.
    """
    речі = кольоронесучі(E)
    if len(речі) < C["мін_слотів"]:
        return []
    out = []
    for i in range(len(речі)):
        for j in range(i + 1, len(речі)):
            a, b = речі[i], речі[j]
            _f = МЕТРИКИ[метрика][0]
            d = _f(a["lab"], b["lab"])
            w = 1.0
            якщо_площі = a.get("площа") is not None and b.get("площа") is not None
            if зважувати_площею and якщо_площі:
                w = float(a["площа"]) * float(b["площа"])
            out.append(dict(a=a["річ"], b=b["річ"], відстань=round(d, 4),
                            ΔE00=round(cs.de00(a["lab"], b["lab"]), 2),
                            метрика=метрика, одиниці=МЕТРИКИ[метрика][1],
                            вага=round(w, 4), площі_є=якщо_площі))
    return out


def середня_близькість(E, зважувати_площею=False, метрика="oklab"):
    """Одне число на образ: середня попарна відстань. Менше = скоординованіше.
    None, коли кольоронесучих слотів менше двох — правило тоді не вдає, що знає.

    ЧОМУ БІЛЬШЕ НЕ ΔE00 (це не смак, це арифметика). Усереднення попарних
    відстаней визначене лише там, де відстань — МЕТРИКА. ΔE00 нею не є і не
    обіцяє бути: на 24 реальних кольорах каталогу 2.98% трійок порушують
    нерівність трикутника, і найгірший випадок — найбанальніший образ, який
    існує: чорний→молочний = 84.6, а через сірий 38.9+27.4 = 66.3. Тобто
    «середня близькість» рахувалась на величині, для якої середнє не визначене.
    У OKLab порушень 0 із 6072 — середнє й центроїд законні.

    ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after, виміряно): на 300 наборах по 6 образів
    дві метрики обирають РІЗНИЙ найскоординованіший образ у 37.0% наборів.
    Це не третій знак після коми, це інша рекомендація в третині випадків.

    ДЕ ЛАМАЄТЬСЯ, І ЦЕ ГОЛОВНЕ ЗАСТЕРЕЖЕННЯ. Виміряно, що метрики РОЗХОДЯТЬСЯ,
    але НЕ виміряно, яка з них ближча до людського вердикту: жодна людина не
    сказала «носитиму / ні» на жодній із 37%. Законність усереднення — доказ
    того, що стара операція була НЕВИЗНАЧЕНА, а не того, що нова ПРАВИЛЬНА.
    Gray та ін. 2014 міряли ранг усередині палітри, а ранг сам залежить від
    метрики, тож перенести їхнє калібрування «як є» не можна. Параметр
    лишається відкритим саме тому: обидві гілки мають бути в A/B-стенді."""
    пари = пари_близькості(E, зважувати_площею, метрика)
    if not пари:
        return None
    if зважувати_площею and all(p["площі_є"] for p in пари):
        W = sum(p["вага"] for p in пари) or 1.0
        return round(sum(p["відстань"] * p["вага"] for p in пари) / W, 4)
    return round(sum(p["відстань"] for p in пари) / len(пари), 4)


