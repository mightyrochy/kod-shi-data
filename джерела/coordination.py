def розклад_пари(lab1, lab2):
    """Точний розклад d_ok на дві ортогональні складові: ІНТЕНСИВНІСТЬ і ТОН.

    ЧОМУ ЦЕ ПОТРІБНО, І ЧОМУ ЦЕ НЕ КОСМЕТИКА. K-COMP-01 каже: середина діапазону
    координації краща за максимум, тобто РОЗБІЖНІСТЬ між речами до певної межі
    БАЖАНА. Але d_ok — один скаляр, і він не знає, ЧИМ саме образ розбігається.
    Наслідок, який видно лише на розкладі: ціль «помірна координація» можна
    задовольнити, роздувши ХРОМУ замість тону. Рівно цей провал тема-4 PART IV і
    називає своїм єдиним прикладом: приглушена шавлія + неонова іржа має ту саму
    відносину тонів, що приглушена шавлія + приглушена іржа, а працює лише друга.
    Поки відстань нерозкладена, обидві пари для системи — просто «дальша» й
    «ближча», і K-COMP-01 сам по собі радо вибере дальшу.

    Розклад точний, не наближений: d_ok² = інтенсивність² + тон².
      · dab   = відстань у площині (a,b) OKLab
      · dC    = різниця хром; |dC| ≤ dab завжди (нерівність трикутника в площині)
      · тон   = √(dab² − dC²) — довжина хорди, яку дає ЛИШЕ поворот тону
      · інт.  = √(dL² + dC²) — те, що корпус зве «chroma and value»
    """
    L1, a1, b1 = cs.to_oklab(lab1)
    L2, a2, b2 = cs.to_oklab(lab2)
    C1, C2 = math.hypot(a1, b1), math.hypot(a2, b2)
    dL, dC = L2 - L1, C2 - C1
    dab = math.hypot(a2 - a1, b2 - b1)
    тон = math.sqrt(max(0.0, dab * dab - dC * dC))
    h1 = math.degrees(math.atan2(b1, a1)) % 360
    h2 = math.degrees(math.atan2(b2, a2)) % 360
    dh = abs(h2 - h1)
    return dict(d_ok=round(math.hypot(dL, dab), 4),
                інтенсивність=round(math.hypot(dL, dC), 4),
                тон=round(тон, 4),
                dL=round(dL, 4), dC=round(dC, 4),
                dh_град=round(min(dh, 360 - dh), 1),
                C1=round(C1, 4), C2=round(C2, 4))


def інтенсивність(E, зважувати_площею=False):
    """K-COMP-04. Розрив ХРОМИ між кольоронесучими речами образу.

    ЧИЙ ЦЕ БІК (архітектурна вимога задачі). КОД. Це впорядкування кандидатів за
    виміряним числом; модель тут не має що додати й не має права переважити.

    ЯКІ ВУЗЛИ ЗВʼЯЗУЄ (вимога гіперграфа). Не звʼязує — і тому це НЕ правило рівня
    гіперребра. Воно попарне між кольоронесучими речами незалежно від того, чи
    вони стикаються на тілі: неонова сумка бʼється з приглушеним верхом, не
    торкаючись його. Тому воно й живе тут, а не в `hypergraph.ребра`.

    ЧОМУ ЛИШЕ ХРОМА, ХОЧ КОРПУС КАЖЕ «chroma AND value». Дві причини, обидві
    перевірні:
      1. Опрацьований приклад самого корпусу ізолює хрому: L_ok 0.665 проти 0.682 —
         світлоти майже рівні, розходиться лише хрома. Тобто те, що приклад ДОВОДИТЬ,
         — це хрома.
      2. Розрив світлоти вже має власника: `outfit.перевірка_value` і контрастні
         правила. Додати його сюди означало б тихого семантичного двійника —
         дефект, який Gate D ловить окремо. Одне рішення — один власник.
    Розходження з текстом корпусу назване тут навмисно, а не замовчане.

    СИЛА `hint`, І ЦЕ НЕ СКРОМНІСТЬ. Тема-4 дає K-COMP-04 `strong`, тема-3 §7.1 те
    саме твердження знімає: Ou & Luo кажуть «той самий тон АБО та сама хрома», а не
    «хрома важливіша», і модель Ou на одязі дає кореляцію −0.02. Суперечність тем
    вирішується слабшою оцінкою. Плюс шкала — з ОДНОГО прикладу (T3). `hint` — це
    рівно те, на що є доказ.

    ДЕ ЛАМАЄТЬСЯ: свідомий high-low контраст інтенсивності як модний сигнал (тема-4
    називає це прямо) — тоді розрив навмисний і правило має мовчати. Розрізнити їх
    код не вміє: наміру в нього нема. Тому hint, а не гейт.
    """
    речі = кольоронесучі(E)
    if len(речі) < C["мін_слотів"]:
        return []
    пари = []
    for i in range(len(речі)):
        for j in range(i + 1, len(речі)):
            a, b = речі[i], речі[j]
            р = розклад_пари(a["lab"], b["lab"])
            р.update(a=a["річ"], b=b["річ"])
            пари.append(р)
    гірша = max(пари, key=lambda p: abs(p["dC"]))
    розрив = abs(гірша["dC"])
    лаг, повн = C["хрома_координує"], C["хрома_рве"]
    if розрив <= лаг:
        return []                      # інтенсивності збігаються — правило мовчить
    return [dict(O._зн(
        "K-COMP-04", "hint",
        "розрив хроми %.3f OKLab між «%s» і «%s»" % (розрив, гірша["a"], гірша["b"]),
        [гірша["a"], гірша["b"]],
        "хроми %.3f і %.3f при різниці тонів %.0f°. Корпус: сумісність тримається "
        "близькістю ІНТЕНСИВНОСТІ, а не відносиною тонів — приглушений із приглушеним "
        "координується за будь-якого тону, приглушений із неоновим ні. Тут частка "
        "інтенсивності в загальній відстані %.0f%%"
        % (гірша["C1"], гірша["C2"], гірша["dh_град"],
           100 * гірша["інтенсивність"] / max(1e-9, гірша["d_ok"])),
        ремонт=["звести хроми до одного регістру: або приглушити гучнішу річ, або "
                "підняти хрому тихішої — тон при цьому міняти не треба"],
        запит=dict(слот=None,
                   хрома_біля=round(min(гірша["C1"], гірша["C2"]), 3),
                   чому="K-COMP-04: збігатись інтенсивністю, тон вільний"),
        ламається="свідомий high-low контраст інтенсивності як модний сигнал — тоді "
                  "розрив навмисний. Наміру код не бачить. Плюс обидві межі зчитані "
                  "з ОДНОГО опрацьованого прикладу корпусу (T3), а тема-3 §7.1 знімає "
                  "силу цього правила зі `strong` до слабшої оцінки",
        вимір=розрив, поріг=лаг, повна=повн,
        reg=РЕЄСТР, рег_карта=РЕГІСТР_ПРАВИЛА),
        сила_нп_джерело="вимір (власний: розрив хроми проти опрацьованого прикладу корпусу)",
        розрив_хроми=round(розрив, 4), пари=пари)]


# ─────────────────────────── 2. РАНГ У НАБОРІ, НЕ АБСОЛЮТНИЙ ПОРІГ ───────────────────────────
def розкид_набору(значення, метрика="oklab"):
    """Чи МОЖНА взагалі ранжувати цей набір кандидатів.

    Тема-3 §5.2 називає це прямо як місце поломки: набір без розкиду (весь
    нейтральний ретрив) → z-скор це шум. Тут поріг не з голови: розкид має
    перевищувати підлогу шуму ΔE00 на некаліброваному каталожному фото."""
    чисті = [v for v in значення if v is not None]
    if len(чисті) < 3:
        return dict(можна=False, чому="менше трьох кандидатів із виміряним кольором — "
                                      "рангу не існує", розкид=None, n=len(чисті))
    _підлога = C[МЕТРИКИ[метрика][2]]
    _од = МЕТРИКИ[метрика][1]
    розкид = max(чисті) - min(чисті)
    можна = розкид >= _підлога
    return dict(
        можна=можна, розкид=round(розкид, 2), n=len(чисті),
        σ=round(statistics.pstdev(чисті), 2),
        метрика=метрика, одиниці=_од, підлога=_підлога,
        чому=("розкид %.4g %s ≥ підлоги шуму %.4g — ранжувати можна"
              % (розкид, _од, _підлога) if можна else
              "розкид %.4g %s нижчий за підлогу шуму %.4g: набір кандидатів не має "
              "колірної варіації, і ранг був би шумом вимірювання, а не сигналом. "
              "Правило УТРИМУЄТЬСЯ" % (розкид, _од, _підлога)))


def ранг_у_наборі(значення, набір):
    """Позиція значення серед кандидатів, 0.0 = найскоординованіший (найменша ΔE),
    1.0 = найрозбіжніший. Саме ця відносність і є тим, що Gray виміряв: z-скор
    усередині палітри, а не абсолютна відстань."""
    чисті = sorted(v for v in набір if v is not None)
    if значення is None or len(чисті) < 2:
        return None
    нижче = sum(1 for v in чисті if v < значення)
    рівних = sum(1 for v in чисті if v == значення)
    return round((нижче + 0.5 * рівних) / len(чисті), 3)


def оцінка_координації(ранг, зсув_вершини=None):
    """Перевернута U на ранзі: 1.0 у вершині, 0.0 на обох краях. НЕПЕРЕРВНА —
    ніяких «зона хороша / зона погана». Обидва краї штрафуються, і це весь сенс:
    надкоординація карається так само, як розлад."""
    if ранг is None:
        return None
    з = C["зсув_вершини"] if зсув_вершини is None else float(зсув_вершини)
    вершина = min(0.95, max(0.05, 0.5 + з))
    x = (ранг - вершина) / (вершина if ранг < вершина else (1.0 - вершина))
    return round(max(0.0, 1.0 - x * x), 3)


def вага_в_скорі(частка_бажана=None):
    """Скільки колірна координація має важити в підсумку. Стеля — 0.44 (Gray, жіночий
    набір), і це межа для випадку, де ВСЕ ІНШЕ зафіксовано. На реальному каталозі, де
    крій і посадка різняться між кандидатами, реальна вага менша. Функція існує, щоб
    ніхто не поставив колір вище цієї межі мовчки."""
    ст = C["стеля_шару"]
    if частка_бажана is None:
        return dict(стеля=ст, нота="верхня межа, не рекомендація")
    if частка_бажана > ст:
        return dict(стеля=ст, прийнято=ст,
                    попередження="запитано %.2f при стелі %.2f: координація не може "
                                 "пояснювати більше, ніж вона пояснює навіть у "
                                 "лабораторних умовах, де колір — єдина змінна"
                                 % (частка_бажана, ст))
    return dict(стеля=ст, прийнято=round(частка_бажана, 3))


