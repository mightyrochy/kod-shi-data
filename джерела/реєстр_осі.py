from colorspace import reliability
from реєстр_політика import ПОРЯДОК
from реєстр_тіри import регістр
from реєстр_сила import _ранг

_КОНТРАСТНА_ВІСЬ = ("K-CLR-02", "K-COL-01")     # правила, що спираються на контраст особи
# ── R-PC-03: ЩО САМЕ ДОВІВ RUSSELL, І ЩО КОД ІЗ ЦЬОГО БРАВ ────────────────────
# ЗНАЙДЕНО ПОШУКОМ У ФАЙЛАХ-ТЕМАХ, а не в реєстрі: `тема-2_колір.md` §1104 містить
# R-PC-03, перебудований із першоджерела (Russell, Kramer & Jones 2017, 151 обличчя
# FACES, три вікові смуги, однакове студійне світло). І там сказано прямо те, що
# знімає підставу цього коду:
#
#   практики міряють контраст ВОЛОССЯ↔ШКІРА; Russell міряв РИСУ↔НАВКОЛИШНЮ ШКІРУ
#   (брови, очі, губи — кожна проти власного кільця шкіри, не проти середньої).
#   Волосся в його наборі даних НЕМАЄ ЗОВСІМ. Це різні змінні, і числа стоять
#   лише за другою.
#
# Отже теза «контраст — захищеніша вісь», якою цей код обмежує температурну
# знахідку, спиралась на джерело, що її НЕ ПОКРИВАЄ. Це «сила ≤ верифікація»,
# порушена в мою користь: авторитет позичений у роботи про інший вимір.
#
# НА ЧОМУ ВОНО СТОЇТЬ НАСПРАВДІ — і це в коді, не в літературі: `AXIS_RELIABILITY`.
# На некаліброваному фото надійність осі контрасту 0.85, осі підтону 0.15. Різниця
# 0.70 — ось справжня, виміряна підстава не давати температурній знахідці звучати
# авторитетніше. Вона нічия не позичена й перевіряється одним рядком.
#
# ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after):
#   before — обмеження діяло ЗАВЖДИ, незалежно від джерела. На спектрофотометрі
#            (контраст 1.00, підтон 1.00, різниця 0.00) температурна знахідка все
#            одно понижувалась би — тобто код застосовував поправку на ненадійність
#            вимірювання там, де ненадійності вже НЕМА.
#   after  — обмеження вмикається лише поки різниця надійностей значуща, і гасне
#            разом із нею. Поправка живе рівно стільки, скільки живе її причина.
# ДЕ ЛАМАЄТЬСЯ: поріг значущості 0.20 — конвенція (T3). Виміряного числа, з якого
# розрив надійностей стає достатнім для перевпорядкування регістрів, ніхто не давав.
#
# ЧОГО ТУТ НЕМА Й ЧОМУ (друга половина R-PC-03, чесно не зроблена):
# формула Russell — CF = (skin − feature)/(skin + feature), Мішельсон, ПОКАНАЛЬНО
# й ПОРИСОВО, тобто ДЕВʼЯТЬ чисел, а не одне; брови йдуть ПРОТИЛЕЖНО за знаком до
# очей і губ, тож згортання в один скаляр знищує саме ту структуру, що несе сигнал.
# Реалізувати це зараз НЕМОЖЛИВО: `лабораторія/зони_з_масок.ZONE_MAP` не виробляє
# зон брів і губ, а
# «райдужка» — не та область (Russell бере і смугу шкіри навколо вій). Блокер
# названий у `status.БЛОКЕРИ_МЕРТВИХ`; вигадувати ці зони з наявних масок було б
# вигадуванням виміру.
МІН_РОЗРИВ_НАДІЙНОСТІ = 0.20


def розрив_осей(source="uncontrolled"):
    """(розрив, контраст, підтон). Наскільки вісь контрасту надійніша за вісь
    підтону НА ЦЬОМУ ДЖЕРЕЛІ. Вимір із `colorspace.AXIS_RELIABILITY`, а не
    твердження з літератури."""
    try:
        R = reliability(source)
        к, п = float(R["contrast"]), float(R["undertone"])
    except Exception:
        return None, None, None
    return round(к - п, 3), к, п


def обмежити_слабшу_вісь(зн, source="uncontrolled"):
    """Слабша вісь не звучить авторитетніше за сильнішу — поки вона СПРАВДІ слабша.

    Правимо РЕГІСТР, а не вимір: `сила_нп` лишається як є (це результат виміру);
    обмежується лише заявлений авторитет. Дві осі знову окремо.

    ⚠ ПОПЕРЕДНІЙ ДОКСТРІНГ посилався на прогін `audit_rpc03.py` («84 випадки з 674
    пар»). Такого файлу в проєкті нема, отже число не переперевіряється і спиратись
    на нього не можна. Замість нього — вимір, що відтворюється тут і зараз:
    `розрив_осей(source)`.
    """
    розрив, к, п = розрив_осей(source)
    діє = розрив is not None and розрив >= МІН_РОЗРИВ_НАДІЙНОСТІ
    по_речах = {}
    for z in зн:
        for річ in (z.get("речі") or []):
            по_речах.setdefault(річ, []).append(z)
    обмежено = 0
    if діє:
        for річ, група in по_речах.items():
            стеля = max((_ранг(z.get("сила")) for z in група
                         if z.get("правило") in _КОНТРАСТНА_ВІСЬ
                         and _ранг(z.get("сила")) is not None), default=None)
            if стеля is None:
                continue                  # контрастної знахідки (з відомою силою) нема —
                                          # нічого перебивати; сила поза шкалою виводить
                                          # групу з-під обмеження, а не дає стелю 0
            for z in група:
                if z.get("правило") != "K-COL-06-T": continue
                р = _ранг(z.get("сила"))
                if р is not None and р > стеля:
                    і = len(ПОРЯДОК) - стеля
                    assert 0 <= і < len(ПОРЯДОК), (стеля, і)
                    нова = ПОРЯДОК[і]
                    z["сила_до_обмеження"] = z.get("сила")
                    z["сила"] = нова
                    z["регістр"] = регістр(z["правило"], нова)
                    обмежено += 1
                    z["обмежено"] = (
                        "R-PC-03: вісь контрасту надійніша за вісь підтону на цьому "
                        "джерелі (%.2f проти %.2f, розрив %.2f) — температурна знахідка "
                        "не звучить авторитетніше за контрастну на цій речі (вимір "
                        "сила_нп=%.2f не змінено)" % (к, п, розрив, z.get("сила_нп", 0.0)))
    _слід_rpc03(source, розрив, к, п, діє, обмежено,
                є_температурні=any(z.get("правило") == "K-COL-06-T" for z in зн))
    return зн


def _слід_rpc03(source, розрив, к, п, діє, обмежено, є_температурні):
    """ПРАВИЛО, ЯКЕ ВІДПРАЦЮВАЛО Й НІЧОГО НЕ ЗНАЙШЛО, — ВІДПРАЦЮВАЛО.

    ЩО ЦЕ МІНЯЄ (before/after). before: `обмежити_слабшу_вісь` спрацьовує 0 разів на
    150 образах × 3 джерела — виміряно. Причина не в тому, що правило зламане, а в
    ланцюгу: обмежувати можна лише K-COL-06-T; вікно температури нейтралі на
    некаліброваному фото має ширину b* ≈ [−31..42] (бо надійність підтону 0.15),
    тож жодна реальна нейтраль із нього не випадає; отже температурних знахідок
    нема, отже обмежувати нічого. Вісь підтону МОВЧИТЬ ЗА ПРИЗНАЧЕННЯМ, і це
    правильна робота «сила ≤ верифікація» — просто невидима.
    after: у лозі стоїть, що вісь перевірена, з числами надійностей. Стиліст бачить
    різницю між «температуру не дивились» і «температуру подивились і не мали чого
    сказати при цій якості входу».
    """
    try:
        import trace as _СЛ
    except Exception:
        return
    if розрив is None:
        return
    if not діє:
        напрям = ("розрив надійностей %.2f < %.2f — осі рівноцінні, обмеження ВИМКНЕНЕ"
                  % (розрив, МІН_РОЗРИВ_НАДІЙНОСТІ))
    elif обмежено:
        напрям = "обмежено %d температурних знахідок" % обмежено
    elif not є_температурні:
        напрям = ("температурних знахідок нема: вісь підтону втрималась при "
                  "надійності %.2f — обмежувати нічого" % п)
    else:
        напрям = "температурні знахідки є й уже не вищі за контрастні"
    _СЛ.запис("R-PC-03", "порядок доказовості осей", "реєстр_правил.обмежити_слабшу_вісь",
              значення="контраст %.2f / підтон %.2f (джерело %s)" % (к, п, source),
              сила=round(розрив, 3), напрям=напрям)
