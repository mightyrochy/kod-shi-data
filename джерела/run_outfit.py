def _зібрати(речі, тіло):
    """Найпростіше збирання: по одній найдешевшій моделі на слот верх/низ/взуття."""
    образ, взято = [], set()
    for сл in ("верх", "низ", "взуття"):
        канд = [r for r in речі if r["слот"] == сл and r["group_id"] not in взято]
        if not канд: continue
        r = min(канд, key=lambda x: x["ціна"])
        взято.add(r["group_id"])
        H = тіло["висоти"]
        гео = {"верх": (H["плечі"], H["стегна"]), "низ": (H["талія"], H["коліно"]),
               "взуття": (10.0, 0.0)}[сл]
        образ.append(dict(r, верх_см=гео[0], низ_см=гео[1], площа=0.33, near=0.9 if сл == "верх" else 0.1,
                          текстура="smooth-matte", крій="straight"))
    return образ if len(образ) >= 2 else None


def _усі_знахідки(вих):
    зн = []
    for ст in (вих.get("стани") or {}).values():
        # `для_стиліста` віддає СПИСОК на стан (виправлено 24.08.2026, див. composer._оцінити)
        зн += list((ст.get("знахідки") if isinstance(ст, dict) else ст) or [])
    зн += list((вих.get("посадка") or {}).get("знахідки") or [])
    к = вих.get("композиція") or {}
    for ключ in ("вето_покриття", "крок_редагування", "підлога_інтересу",
                 "тканина_проти_крою", "масштаби"):
        зн += list(к.get(ключ) or [])
    return зн


