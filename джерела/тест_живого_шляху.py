"""ЖИВИЙ ШЛЯХ ПРОДУКТУ, ПРОГНАНИЙ ЦІЛКОМ, З ЧЕСНИМ КОДОМ ВИХОДУ.

ЧОМУ ЦЕЙ ФАЙЛ Є (V02, вага «критично»). Під наміром `statement` /
`fashion_forward` на `каталог_brief.xml` — тобто на тому самому фіді, що їде в
артефакт (`build_артефакт.py: ФІД = "каталог_brief.xml"`) — `composer.зібрати`
кидає `ValueError: однакові id речей`, `bridge._пакет_каталогу` ловить його
загальним `except` і чесно віддає `готово=False`. Далі пул порожній, промпт тихо
падає в прозовий формат, і чотири прогони поспіль це читалось як «модель не
слухається формату». ЖОДЕН прилад проєкту цього не бачив: `стенд_знімок --дим`
не ходить у каталог, `гейти_нові.py` §41 ганяє рівно цей вхід і лишається
зеленим (див. там же), `gate_reach` під `statement` не передавав ключ `каталог`
і тому в composer не заходив. Поломка на найважливішому шляху жила в коді, а всі
три прилади звітували «зелено».

ЩО ЦЕ МІРЯЄ. Шість викликів моста ПОСЛІДОВНО, тим самим порядком, яким їх кличе
`показ.html`: `паспорт` → `палітри` → `запити` → `від_моделі` → `опис` → `показ`.
Матриця: `стенд_вх.json` × `каталог_brief.xml` × {гілка None, 0} × {conventional,
fashion_forward, statement} = 6 прогонів. `гілка=None` («хай вирішує ші») —
дефолт показу, `гілка=0` — «людина обрала схему»: це два різні шляхи коду.

ЩО ВВАЖАЄТЬСЯ ПРОВАЛОМ (рівно три речі, без вигаданих порогів):
  · виняток на будь-якому кроці;
  · `пул_речей == 0` — модель не побачила жодної речі;
  · `готово=False` у будь-якому вигляді, яким міст його називає:
    `помилка` (палітри), `пул_чому` (запити), `перевірено=False` (від_моделі).
Провал → `sys.exit(1)`. Тиша й `0` — успіх.

ЧОГО ЦЕ НЕ ДОВОДИТЬ. Що образ ГАРНИЙ. Тут не оцінюється жодна знахідка й жодна
сила: міряється лише те, що ланцюг не рветься і що на кожному кроці є з чим
працювати далі. Вердикт про якість дають `стенд_знімок.py` і `гейти_нові.py`.

Прогін:  python3 тест_живого_шляху.py            (хвилини, офлайн, детермінований)
         python3 тест_живого_шляху.py --каталог каталог_повний.xml
"""
import sys, os, json, argparse, tempfile, traceback

ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ТУТ)
os.chdir(ТУТ)

# ФІД ЗА ЗАМОВЧУВАННЯМ — ТОЙ, ЩО ЇДЕ В АРТЕФАКТ, а не найбільший із наявних.
# `каталог_повний.xml` на V02 НЕ ламається (комплекти не потрапляють у топ-5
# ядра), `каталог_brief.xml` ламається на всіх сідах — і саме brief лежить
# усередині вантажу показу. Прилад, що ганяє не той каталог, звітував би зелено
# про поламаний продукт; це вже сталося тричі.
КАТАЛОГ = "каталог_brief.xml"
ГІЛКИ = (None, 0)
НАМІРИ = ("conventional", "fashion_forward", "statement")

# Синтетична відповідь моделі на виклик 0 — рівно та форма, яку оголошує
# `pipeline.СХЕМА_ПАСПОРТА`. Модель тут не потрібна: міряється шов, не модель.
ПАСПОРТ_МОДЕЛІ = {
    "подія": "робочий день в офісі",
    "формат": "приміщення",
    "тривалість_год": 9,
    "рух": "сидіти",
    "дрес_код": "business_casual",
    "ошатність": [4, 6],
    "година": 9, "темп_c": 18, "опади": "ні",
    "намір": "conventional",
    "бажання": ["щось зі структурою"],
    "вето": {"типи": [], "тканини": [], "принти": [], "кольори": [], "зони": []},
    "ноги_вище_см": None,
    "настрій": ["зібрано"],
    "невідомо": ["взуття"],
}
# НАМІР ЖИВЕ В ПАСПОРТІ, А НЕ ПОРУЧ ІЗ НИМ. `bridge._застосувати_паспорт` бере
# `намір` із паспорта і перекриває ним поле верхнього рівня — рівно так само, як
# `показ.html: намір: (ПАСПОРТ_П && ПАСПОРТ_П.намір) || 'conventional'`. Перша
# версія цього файла ставила намір лише на верхньому рівні, паспорт мовчки
# повертав його в `conventional`, і всі шість прогонів були одним прогоном:
# однакові 214/207 речей, шість зелених рядків над зламаним `statement`. Тобто
# прилад проти мовчазної підміни сам її й зробив.

# Ядро образу: перший слот кожної пари береться, якщо в ньому є кандидати.
# «сукня» або «комплект» замінюють пару верх+низ — той самий вибір, що робить
# `outfit.елементи`, тож синтетичний образ не порушує структурних правил.
ПАРИ_ЯДРА = (("сукня", "комплект", "верх"), ("низ",), ("взуття",), ("сумка",))


class Провал(Exception):
    """Крок не дав того, без чого наступний крок не має сенсу."""


def _ядро_образу(кандидати):
    """Синтетичний образ моделі: РЕАЛЬНІ id з пулу, по одному на слот ядра.

    Модель тут не кличеться — вона в цьому тесті й не потрібна: вимірюється, чи
    приймає `від_моделі` те, що сам код щойно віддав як кандидатів. Якщо перший
    слот пари порожній, береться наступний; порожня пара пропускається.
    """
    речі = []
    for пара in ПАРИ_ЯДРА:
        for слот in пара:
            пул = кандидати.get(слот) or []
            if пул:
                речі.append(dict(id=пул[0]["id"], слот=слот,
                                 назва=пул[0].get("назва")))
                break
        if len(речі) >= 4:
            break
    return речі


def прогін(вх_база, гілка, намір, докладно=False):
    """Шість викликів моста поспіль. Повертає список рядків звіту; кидає `Провал`."""
    import bridge as B
    рядки = []
    вх = dict(вх_база, намір=намір)
    if гілка is None:
        вх.pop("гілка", None)
    else:
        вх["гілка"] = гілка

    # ── 1. ПАСПОРТ. Виклик 0: що модель зрозуміла про випадок ────────────────
    # `json_моделі` — РЯДОК, а не словник: `pipeline.паспорт_з_json` дістає JSON
    # із сирого тексту відповіді (```json …``` або перша фігурна дужка). Словник
    # там перетворюється на `str(dict)` з одинарними лапками, `json.loads` падає,
    # і паспорт мовчки виходить із дефолтами сценарію (`джерело="сценарій (модель
    # не відповіла)"`). Перша версія цього файла так і робила — і тому міряла
    # НЕ той шлях, який кличе показ.
    п = json.loads(B.виклик("паспорт", json.dumps(
        dict(json_моделі=json.dumps(dict(ПАСПОРТ_МОДЕЛІ, намір=намір),
                                    ensure_ascii=False),
             сценарій=вх.get("сценарій") or {},
             вимоги=вх.get("вимоги") or ""), ensure_ascii=False)))
    if not (п.get("паспорт") and п.get("випадок")):
        raise Провал("паспорт: %s" % json.dumps(п, ensure_ascii=False)[:200])
    if (п["паспорт"].get("джерело") or "") != "модель":
        raise Провал("паспорт: синтетичний JSON не розібрано, джерело «%s»"
                     % п["паспорт"].get("джерело"))
    пасп = dict(п["паспорт"])
    # СЛОВНИК ПАСПОРТА ВУЖЧИЙ ЗА СЛОВНИК КОДУ, І ЦЕ НЕ МОЖНА ЗАМОВЧАТИ.
    # `паспорт_з_json` приймає лише `conventional | statement`, а `composer`
    # знає три сміливі наміри (`fashion_forward`, `statement`, `editorial`).
    # `_застосувати_паспорт` бере намір ІЗ ПАСПОРТА і перекриває ним поле
    # верхнього рівня — тож `fashion_forward` через паспорт тихо стає
    # `conventional`, і матриця з шести прогонів була б одним прогоном.
    # Тут ключ знімається, коли паспорт звузив намір: тоді діє вибір верхнього
    # рівня (те саме робить показ, коли паспорта ще нема). Звуження не
    # ховається — воно стоїть у рядку звіту.
    звужено = пасп.get("намір") != намір
    if звужено:
        пасп.pop("намір", None)
    вх["паспорт"] = пасп
    рядки.append("паспорт «%s», джерело %s%s"
                 % (str(п["випадок"])[:44], пасп.get("джерело"),
                    ", намір звужено паспортом до «%s» — беремо верхній"
                    % (п["паспорт"].get("намір")) if звужено else ""))

    # ── 2. ПАЛІТРИ. Розвилка схем, з якої людина обирає гілку ────────────────
    пал = json.loads(B.виклик("палітри", json.dumps(вх, ensure_ascii=False)))
    if пал.get("помилка"):
        raise Провал("палітри: %s" % пал["помилка"])
    if not (пал.get("гілки") or []):
        raise Провал("палітри: розвилка порожня")
    рядки.append("палітри: гілок %d, реалізованих %d"
                 % (len(пал["гілки"]), пал.get("схем_показано") or 0))

    # ── 3. ЗАПИТИ. Тут і живе V02: пул або є, або його нема ──────────────────
    з = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    if з.get("помилка"):
        raise Провал("запити: %s" % з["помилка"])
    if з.get("пул_чому"):
        raise Провал("запити, готово=False: %s" % з["пул_чому"])
    if not (з.get("пул_речей") or 0):
        raise Провал("запити: пул_речей=0 без названої причини")
    кандидати = з.get("кандидати") or {}
    речі = _ядро_образу(кандидати)
    if len(речі) < 2:
        raise Провал("запити: у пулі %d речей, але ядро образу не складається "
                     "(слоти: %s)" % (з["пул_речей"], sorted(кандидати)))
    рядки.append("запити: пул %d, слотів %d, ядро %s"
                 % (з["пул_речей"], len(кандидати),
                    "+".join(р["слот"] for р in речі)))

    # ── 4. ВІД_МОДЕЛІ. Код судить образ, зібраний із власних кандидатів ──────
    вм = json.loads(B.виклик("від_моделі", json.dumps(
        dict(вх, ід=[р["id"] for р in речі]), ensure_ascii=False)))
    if вм.get("перевірено") is False:
        raise Провал("від_моделі, готово=False: %s" % вм.get("чому"))
    рядки.append("від_моделі: знахідок %d, питань %d, ребер %s"
                 % (len(вм.get("знахідки") or []), len(вм.get("питання") or []),
                    (вм.get("граф") or {}).get("ребер")))

    # ── 5. ОПИС. Промпт опису обраного образу + адреси фото ──────────────────
    оп = json.loads(B.виклик("опис", json.dumps(
        dict(вх, речі=речі, підпис="прогін живого шляху"), ensure_ascii=False)))
    if not (оп.get("промпт") or "").strip():
        raise Провал("опис: промпт порожній")
    if len(оп.get("речі") or []) != len(речі):
        raise Провал("опис: речей на вході %d, на виході %d"
                     % (len(речі), len(оп.get("речі") or [])))
    рядки.append("опис: промпт %d символів, фото %d"
                 % (len(оп["промпт"]), len(оп.get("фото") or [])))

    # ── 6. ПОКАЗ. Картки, які людина побачить очима ──────────────────────────
    пк = json.loads(B.виклик("показ", json.dumps(
        dict(вх, речі=речі), ensure_ascii=False)))
    if len(пк) != len(речі):
        raise Провал("показ: карток %d на %d речей" % (len(пк), len(речі)))
    if [к["id"] for к in пк] != [р["id"] for р in речі]:
        raise Провал("показ: id карток не збігаються з речами образу")
    # Порожня картка — не провал ланцюга (фід міг не мати фото), але число
    # видно: без нього «показ пройшов» нічого не каже про те, що побачить око.
    рядки.append("показ: карток %d, із фото %d, з ціною %d"
                 % (len(пк), sum(1 for к in пк if к.get("фото")),
                    sum(1 for к in пк if к.get("ціна"))))
    if докладно:
        рядки.append("       речі: " + " · ".join(
            "%s %s" % (р["слот"], str(р.get("назва") or р["id"])[:28]) for р in речі))
    return рядки


def main(argv=None):
    р = argparse.ArgumentParser(description="живий шлях продукту з кодом виходу")
    р.add_argument("--каталог", default=КАТАЛОГ)
    р.add_argument("--вхід", default="стенд_вх.json")
    р.add_argument("--докладно", action="store_true")
    а = р.parse_args(argv)

    вх_база = json.load(open(а.вхід, encoding="utf-8"))
    # ШЛЯХ ДО КАТАЛОГУ — ЧЕРЕЗ `feed.каталог_на_диску`, а не голим іменем: у git
    # лежить `каталог_brief.xml.gz` (261 КБ), розпакований файл у `.gitignore`.
    # `bridge._каталог_із` бере `d["каталог"]` як є і .gz не знає, тож на чистому
    # клоні голе ім'я дало б `FileNotFoundError` замість прогону.
    import feed as _Ф
    вх_база["каталог"] = _Ф.каталог_на_диску(а.каталог)
    # Кеш кольорів окремий і ПОЗА репозиторієм: прогін не має права ні псувати
    # кеш стенда, ні ставати швидшим від того, що стенд бігав перед ним, ні
    # лишати в дереві файл, який доводиться заганяти в `.gitignore`. Ім'я стале —
    # повторний прогін тим самим каталогом не міряє фото вдруге (той самий
    # прийом, що `gate_reach` уже застосовує до `гейт_каталог.xml`).
    вх_база["кеш_кольорів"] = os.path.join(tempfile.gettempdir(),
                                           "кеш_живого_шляху.json")
    if not os.path.exists(вх_база["кеш_кольорів"]):
        json.dump({}, open(вх_база["кеш_кольорів"], "w"))

    print("=" * 78)
    print("ЖИВИЙ ШЛЯХ: паспорт → палітри → запити → від_моделі → опис → показ")
    print("вхід %s × каталог %s × гілки %s × наміри %s"
          % (а.вхід, а.каталог, ГІЛКИ, "/".join(НАМІРИ)))
    print("=" * 78)

    збої = []
    for гілка in ГІЛКИ:
        for намір in НАМІРИ:
            мітка = "гілка=%-4s намір=%-16s" % ("—" if гілка is None else гілка, намір)
            try:
                рядки = прогін(вх_база, гілка, намір, докладно=а.докладно)
            except Провал as e:
                збої.append((мітка, str(e)))
                print("  ✗ %s ПРОВАЛ: %s" % (мітка, e))
            except Exception as e:
                збої.append((мітка, "%s: %s" % (type(e).__name__, e)))
                print("  ✗ %s ВИНЯТОК: %s: %s" % (мітка, type(e).__name__, e))
                if а.докладно:
                    traceback.print_exc()
            else:
                print("  ✓ %s" % мітка)
                for р_ in рядки:
                    print("       %s" % р_)

    print("=" * 78)
    print("ПРОЙДЕНО %d, ВПАЛО %d із %d"
          % (len(ГІЛКИ) * len(НАМІРИ) - len(збої), len(збої), len(ГІЛКИ) * len(НАМІРИ)))
    for мітка, чому in збої:
        print("  ВПАЛО: %s %s" % (мітка, чому))
    print("=" * 78)
    return 1 if збої else 0


if __name__ == "__main__":
    sys.exit(main())
