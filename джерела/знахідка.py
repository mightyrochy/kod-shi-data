# ── ФОРМА ЗНАХІДКИ ───────────────────────────────────────────────────────────
# Обов'язкові поля: за ними знахідка й розпізнається в чужому дереві.
# `правило` + хоч одне з `суть`/`чому` — мінімум, за яким її можна показати людині.
ОБОВʼЯЗКОВІ = ("правило",)
ЗМІСТОВІ = ("суть", "чому")

# П'ять сил корпусу, за спаданням. Копія `outfit.ПОРЯДОК` навмисно НЕ робиться:
# порядок сил живе в `outfit`, і другий список розійшовся б із першим.
# Тут лише ті значення, що силою НЕ є, — вони позначають стан входу, не вагу.
НЕ_СИЛИ = ("питання", "утримано")

# Регістри: гейт відкидає, репліка промовляє, питання каже, що входу нема.
РЕГІСТРИ = ("гейт", "репліка", "питання")


def це_знахідка(o):
    """Чи виглядає dict як знахідка. Форма, а не місце — у цьому й сенс."""
    return (isinstance(o, dict)
            and all(k in o for k in ОБОВʼЯЗКОВІ)
            and any(k in o for k in ЗМІСТОВІ))


def усі(вихід, корінь=""):
    """[(шлях, знахідка)] — усе дерево, а не названі відра.

    Обхід зупиняється на самій знахідці й усередину неї не лізе: поля `речі`,
    `ремонт`, `запит_у_каталог` можуть містити словники, і без цієї зупинки
    ремонт однієї знахідки читався б за другу.
    """
    out = []
    if isinstance(вихід, dict):
        if це_знахідка(вихід):
            out.append((корінь, вихід))
        else:
            for k, v in вихід.items():
                out += усі(v, корінь + "/" + str(k))
    elif isinstance(вихід, (list, tuple)):
        for v in вихід:
            out += усі(v, корінь)
    return out


def список(вихід):
    """Лише знахідки, без шляхів — для викликача, якому шлях не потрібен."""
    return [з for _, з in усі(вихід)]


def без_повторів(пари):
    """Знахідка може лежати у двох відрах законно (ворота + преференції).

    Ключ дедуплікації — правило + суть + речі: те, що людина побачить як один
    рядок. Порядок зберігається: перше входження виграє, бо відра йдуть у порядку
    від жорсткіших до м'якших.
    """
    бачені, out = set(), []
    for ш, з in пари:
        к = (з.get("правило"), str(з.get("суть"))[:120],
             tuple(sorted(str(r) for r in (з.get("речі") or []))))
        if к in бачені:
            continue
        бачені.add(к)
        out.append((ш, з))
    return out


def припущення(пари):
    """Знахідки, що позначають ВІДСУТНІЙ ВХІД, а не вердикт (K-IO-03, hard).

    Корпус вимагає, щоб кожне припущення стояло явним блоком, а не мовчки в
    числах. Тому це окремий вихід, а не фільтр на боці викликача: фільтр на боці
    викликача вже один раз загубив ціле відро.
    """
    out = []
    for _, з in пари:
        if з.get("сила") in НЕ_СИЛИ or з.get("регістр") == "питання":
            out.append(dict(правило=з.get("правило"),
                            що=str(з.get("суть", ""))[:90],
                            чому=str(з.get("чому", ""))[:160] or None))
    return out
