def _норм_тір(t):
    """Тір -> клас доказу, або None для дефініційних. Невідомий рядок — найслабший
    клас, і це навмисно: незнайомий тір не має права давати правилу більше прав."""
    return _ТІР_НОРМА.get(t, "T3")

def _за_кого(v):
    """ID правил, за які голосує константа реєстру. Приймає обидві форми поля
    «прав» — список (канон) і одиночний рядок (реєстри інших модулів), — щоб
    машинерія інваріанта лишалась одна на всі реєстри. Службова константа
    (`службова=True`, поля «прав» нема) не голосує ні за кого."""
    п = v.get("прав")
    if п is None: return ()
    return tuple(п) if isinstance(п, (list, tuple, set)) else (п,)

def _тір_правила(правило, reg=None):
    """`reg` — реєстр констант. Параметр доданий, щоб інший модуль правил (посадка.py)
    проганяв СВОЇ константи через ЦЮ саму машинерію інваріанта, а не копіював її:
    копія розійшлась би з оригіналом при першій же зміні, і «сила ≤ верифікація»
    трималась би у двох місцях по-різному."""
    reg = REGISTRY if reg is None else reg
    тіри = [_норм_тір(v.get("t")) for v in reg.values() if правило in _за_кого(v)]
    тіри = [t for t in тіри if t]        # дефініційні константи не голосують
    if not тіри: return None
    return min(тіри, key=lambda t: ("T1", "T2", "T3").index(t) * -1)   # найслабший

def стеля_сили(правило, reg=None):
    """Максимальна сила, на яку правило має право за своєю доказовою базою."""
    т = _тір_правила(правило, reg)
    return СТЕЛЯ_ЗА_ТІРОМ.get(т) if т else None

def _обмежити_тіром(правило, сила, reg=None):
    стеля = стеля_сили(правило, reg)
    if стеля is None or сила in ("ok", "питання", "утримано"): return сила, None
    if ПОРЯДОК.index(сила) >= ПОРЯДОК.index(стеля): return сила, None
    return стеля, ("сила знижена з «%s» до «%s»: правило стоїть на константі тіру %s "
                   "(сила ≤ верифікація)" % (сила, стеля, _тір_правила(правило, reg)))


def _обмежити_корпусом(правило, сила, заявлена=None):
    """Другий бік того самого інваріанта (Н-02-05, крок 4 Н-V23-047): емісія не має
    права видати правило СИЛЬНІШИМ, ніж його називає САМ КОРПУС.

    Стеля тіру ловить «доказ під правилом слабкий»; ця — «корпус сказав менше, ніж
    каже код». Дві різні дірки, і друга вже була відкрита: `accessory` емітував
    K-WEA-05 і K-WEA-06 силою `strong` там, де тема-10:1605 і тема-10:1625 дають
    обом `default`. Стеля тіру це зараз перекриває (T3 → soft), але перекриває
    ВИПАДКОВО — досить комусь оголосити під правилом T2-константу, і заявка коду
    знову пішла б понад корпус. Тому стеля береться з того самого рядка політики,
    де вже стоїть `джерело`."""
    к = _політика(правило).get("сила_корпусу")
    if not к or сила in ("ok", "питання", "утримано"): return сила, None
    заявлена = сила if заявлена is None else заявлена
    джерело = _політика(правило).get("джерело") or "джерело не названо"
    if сила in ПОРЯДОК and ПОРЯДОК.index(сила) < ПОРЯДОК.index(к):
        return к, ("сила знижена з «%s» до «%s»: стільки дає правилу корпус (%s)"
                   % (сила, к, джерело))
    # ── ЧОМУ ЦЕ ПОЛЕ БУЛО ПОРОЖНЄ ЗАВЖДИ (19.09.2026, РВ-5 З-5) ──────────────
    # Виміряно пробою `аудит/проби/рв5_стеля_корпусу.py`: у жодній із шести
    # стендових сцен `стеля_корпусу` не з'являлась ЖОДНОГО разу, працювала лише
    # `стеля_тіру`. Причина не в тому, що код ніде не заявляє понад корпус, — він
    # заявляє: `accessory` кличе K-WEA-05 і K-WEA-06 силою `strong` там, де
    # тема-10:1605/1625 дають обом `default`, `fit` кличе K-FIT-01 силою `strong`
    # при корпусному `soft`. Причина в ПОРЯДКУ: тір іде першим (і це навмисно,
    # див. `_зн`), а в КОЖНОМУ рядку таблиці стеля тіру (T3 → soft) не вища за
    # силу корпусу. Друга стеля діставала вже зрізану силу, і їй не лишалось чого
    # знижувати — заявка коду понад корпус зникала за нотою про тір.
    # Стеля корпусу могла б ЗНИЗИТИ силу лише там, де під правилом оголошено
    # константу T1/T2, а корпус при цьому свідомо дає менше; жодного такого рядка
    # в таблиці сьогодні нема, і це факт про таблицю, а не привід мовчати.
    # ЩО СТАЛО: стеля міряється ще й проти ЗАЯВЛЕНОЇ сили (тієї, з якою емітент
    # покликав `_зн`). Чинна сила не змінюється — вона й доти була мінімумом обох
    # стель, — але перевищення заявки над корпусом більше не невидиме.
    if (заявлена in ПОРЯДОК and сила in ПОРЯДОК
            and ПОРЯДОК.index(заявлена) < ПОРЯДОК.index(к)):
        return сила, ("емісія заявила «%s», а корпус дає правилу «%s» (%s); чинну "
                      "силу «%s» поставила стеля тіру — вона не вища за корпусну, тож "
                      "знижувати тут уже нічого. Заявка коду понад корпус — факт про "
                      "ЕМІСІЮ, і тепер він названий, а не схований за нотою тіру"
                      % (заявлена, к, джерело, сила))
    return сила, None

