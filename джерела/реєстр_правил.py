# ЗНАЙДЕНО ПЕРЕВІРКОЮ КОДУ ПРОТИ КОРПУСУ: `_тір_правила` робив
# `("T1","T2","T3").index(t)` і падав ValueError на будь-якому іншому рядку. А інші
# рядки в реєстрах Є: "conventional" (посадка ×4, силует ×9, palette ×7, outfit ×5),
