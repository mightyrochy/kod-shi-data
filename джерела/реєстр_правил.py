# впевненість, не силу заборони.
#
# ── НЕВІДОМИЙ ТІР БІЛЬШЕ НЕ ДАЄ ПРАВА НА ГЕЙТ (перевірка V23, наряд Н-V23-046) ──
# ЩО ТУТ СТОЯЛО: регістр питав ЛИШЕ карту — «написано гейт і сила hard/strong,
# отже блокуємо». Тір під правилом не питали жодного разу, і саме на найсильнішому
# регістрі інваріант «сила ≤ верифікація» не діяв узагалі. Зміряно на картах
# чотирьох модулів: з дванадцяти правил, заявлених «гейт», ДЕВ'ЯТЬ блокували образ,
# не маючи під собою ЖОДНОЇ константи з тіром (K-EYE-01, K-GLV-01, K-HAT-01,
# K-SIZ-01, K-WEA-05, K-WEA-06, K-OUT-05, K-OUT-15, K-OUT-41). `_обмежити_тіром`
# їх не чіпав: без константи стеля — None, а None нічого не знижує.
# ЩО СТАЛО: гейт видається лише тоді, коли доказова база під правилом ОГОЛОШЕНА
# і дозволяє hard/strong. Нема константи — нема гейта, і знахідка каже це вголос
# полем `гейт_знято` (мовчазне зняття було б тим самим дефектом навпаки).
ГЕЙТ_БЕЗ_ДОКАЗУ = ("регістр «гейт» заявлено, але під правилом не оголошено жодної "
                   "константи з тіром — доказової бази нема, тож гейт не видається")


def _гейт_без_доказу(правило, сила, reg=None):
    """Чи саме БРАК доказової бази зняв гейт із цієї знахідки.
    Слабка сила під гейтом — інша причина (вона була й до Н-V23-046), і плутати
    їх не можна: «нічим судити» і «судили й вийшло слабко» — різні стани.
    Гейт на МЕЖІ ЛЮДИНИ доказової бази в реєстрі констант не потребує (див.
    `ПОЛІТИКА_ДОК`), тож і зняти його браком тіру не можна."""
    if сила == "питання": return False
    п = _політика(правило)
    if п.get("регістр") != "гейт" or п.get("підстава") == МЕЖА_ЛЮДИНИ: return False
    # ГЕЙТ ВІД КОРПУСУ БРАКОМ ТІРУ НЕ ЗНІМАЄТЬСЯ (19.09.2026). `регістр()` з 16.09
    # видає гейт уже на самій силі корпусу («FORCE: hard» — цього досить), і без
    # цього рядка знахідка вийшла б із блокує=True І з полем `гейт_знято`, тобто
    # сказала б про себе дві протилежні речі. Брак константи з тіром тут не
    # умовчання, а факт про правило: вето категорійне (слово складу), порога нема.
    if п.get("сила_корпусу") in ("hard", "strong"): return False
    return сила in ("hard", "strong") and стеля_сили(правило, reg) is None


def регістр(правило, сила, reg=None):
    """Регістр знахідки — ЄДИНА функція, що його вирішує, з ЄДИНОЇ таблиці.

    `рег_карту` (чужу карту в параметрі) знято Н-02-05: доти кожен викликач мав
    право підсунути свою, і політика розійшлась на шість карт плюс два прямі
    переписування результату. Лишився `reg` — реєстр КОНСТАНТ модуля, з якого
    прийшла знахідка: без нього стеля тіру рахувалась би по REGISTRY ядра, і
    правило accessory/outer щоразу виглядало б беззаконним."""
    # РЕГІСТР БУВ СУТО ПО-ПРАВИЛЬНИЙ, і це втрачало один випадок: правило працює, а
    # ВХОДУ під конкретну річ немає. «Питання» — властивість ВИКЛИКУ, не правила:
    # K-BOD-02 має вхід на полотні й не має його, коли тканина не відома. Доти таке
    # спрацювання виходило реплікою, тобто НЕВІДРІЗНЯЛЬНО від виміряного вердикту, і
    # стиліст не бачив, що під ним бракує входу. Сила «питання» тепер сама себе несе.
    if сила == "питання": return "питання"
    п = _політика(правило)
    р = п.get("регістр", "репліка")
    # СИЛА КОРПУСУ — ДОСТАТНЯ ПІДСТАВА ДЛЯ ГЕЙТА (16.09.2026). Доти корпусне `hard`
    # без константи тіру виходило реплікою («гейт без оголошеного тіру»), і
    # «тип "джинси" не належить до коду business_casual» силою 0.95 нікого не
    # зупиняло: образ ішов у вибір із `перевірено: True`. Корпус каже «FORCE: hard
    # where a code is stated» — цього досить.
    if п.get("сила_корпусу") in ("hard", "strong") and сила in ("hard", "strong"):
        return "гейт"
    if р != "гейт": return р
    # МЕЖА ЛЮДИНИ: доказ — те, що людина це сказала (тема-4:658). Тір не питається,
    # інакше особисте вето втратило б силу рівно там, де корпус її не вимагає.
    if п.get("підстава") == МЕЖА_ЛЮДИНИ: return "гейт"
    if сила in ("hard", "strong") and стеля_сили(правило, reg) in ("hard", "strong"):
        return "гейт"
    return "репліка"      # слабка знахідка навіть механічного правила лише промовляється

# ─────────────────────────── СИЛА ЗНАХІДКИ ───────────────────────────
# ЗНАЙДЕНО ПЕРЕВІРКОЮ КОДУ ПРОТИ КОРПУСУ: словник сил корпусу — П'ЯТИРІВНЕВИЙ
# (hard / strong / default / soft / hint), а тут стояв ЧОТИРИРІВНЕВИЙ: "default"
# бракувало. Наслідок був не косметичний — `ПОРЯДОК.index("default")` кидав
# ValueError, тобто будь-яке правило, що виходить із силою "default", крашило
# перевірку стелі тіру. Не спрацьовувало лише тому, що єдиний носій цієї сили
# (K-COMP-01) свій реєстр у машинерію не передавав; щойно передали — впало.
# `default` стоїть між strong і soft: це сила «діє, поки не спростовано», слабша за
# доказову strong і сильніша за м'яку пораду.
ПОРЯДОК = ["hard", "strong", "default", "soft", "hint"]


def _ранг(сила):
    """Місце сили на ЄДИНІЙ шкалі `ПОРЯДОК`: чим сильніша, тим більший ранг
    (hard = 5 … hint = 1). Невідома сила — «питання», «утримано», «ok», None —
    дає None, а НЕ мовчазний 0.

    ЗНАЙДЕНО Н-outfit-2-090: `обмежити_слабшу_вісь` тримала власний
    чотирирівневий словник сил без "default". Наслідок був подвійний: знахідка
    силою `default` давала стелю 0 (бо `.get(…, 0)`), а пошук імені сили за
    значенням 0 не знаходив нічого і кидав IndexError, який вбивав увесь
    `review()`. Мовчазний 0 однаково небезпечний і для сил поза шкалою: вони
    мають виводити групу З-ПІД обмеження, а не зрізати сусіда до найслабшого.
    Тому шкала одна й повертає None, коли не знає сили."""
    try:
        return len(ПОРЯДОК) - ПОРЯДОК.index(сила)
    except ValueError:
        return None
def _сила(база, вимір, поріг, розкид=None):
    """Сила ≤ верифікація. Поріг некалібрований -> вердикт біля порога не заслуговує
    повної сили правила.

    ДОДАНО ПІСЛЯ ПЕРШОГО РЕАЛЬНОГО ФОТО: маржа рішення має перевищувати ТОЧНІСТЬ
    ВИМІРУ. На дзеркальному селфі та сама спідниця дала L*29.9 у одному місці й
    L*43.3 в іншому — розкид 13 при пороzі кроку світлоти 12. Тобто вердикт залежав
    від того, куди впала маска. Це не другий фольклорний поріг: тут порівнюються дві
    ВИМІРЯНІ величини — маржа рішення проти розкиду зони (extract.zone_stats рахував
    його з самого початку, і досі ним ніхто не користувався)."""
    смуга = abs(поріг) * C["band"] or 1.0
    маржа = abs(вимір - поріг)
    if розкид and маржа < розкид:      # `розкид` тут = ПОХИБКА ОЦІНКИ (se_L), не MAD пікселів
        i = min(ПОРЯДОК.index(база) + 1, len(ПОРЯДОК) - 1)
        return ПОРЯДОК[i], (f"рішення тонше за точність виміру (маржа {маржа:.0f} < "
                            f"розкид зони {розкид:.0f}) — знижено")
    if маржа < смуга:
        i = min(ПОРЯДОК.index(база) + 1, len(ПОРЯДОК) - 1)
        return ПОРЯДОК[i], f"межовий випадок (|{вимір:.0f}−{поріг:.0f}| < {смуга:.0f}) — знижено"
    return база, None

def _репліка(суть, чому):
    """Переклад знахідки з мови вироку в мову спостереження для стиліста-моделі.
    Не «порушено правило X», а «я бачу ось це, ось наскільки виразно» — рішення за
    композитором. Тон описовий: називає видиме, не приписує помилки."""
    основа = суть.split(" — ")[0] if " — " in суть else суть
    основа = основа[0].upper() + основа[1:]
    # `правило` і `впевненість` прибрано з сигнатури: обидва вже їдуть окремими
    # полями знахідки, а тут лише вдавали, що впливають на формулювання.
    return f"{основа}. {чому}"

def _мʼякший_ремонт(ремонт):
    """Ремонт репліки — пропозиція, не імператив. Список лишається (він корисний
    композиторові як напрям пошуку), але подається як опція."""
    if isinstance(ремонт, str):
        return "як варіант — " + ремонт[0].lower() + ремонт[1:]
    return ["як варіанти:"] + ремонт

# СЛОВО НА КОЖНУ СХОДИНКУ ШКАЛИ. `_зн` бере слово через `ВПЕВНЕНІСТЬ.get(сила,
# "злегка")`, тому дірка в словнику не падає, а МОВЧКИ підміняє слово найслабшим.
# Так і було з `hard` (Н-outfit-1-085): найсильніша категорія діставала «злегка».
# Своїх hard-реплік цей модуль не емітує, але рег_карти чужих модулів ходять сюди
# через `_зн(reg=…)`, і hard-репліка звідти говорила стилістові рівно навпаки
# до власної сили. Ключі словника мусять покривати `ПОРЯДОК` — це стереже гейт 142.
# `ok` тут не потрібен і знятий: ok-знахідка (`біля_обличчя`, «контраст у межах»)
# народжується прямим dict-ом повз `_зн`, поля `впевненість` не має взагалі, і
# `_узгодити_слово` її не чіпає. Ключ був би словом, якого нікому сказати.
ВПЕВНЕНІСТЬ = {"hard": "беззаперечно", "strong": "виразно", "default": "як правило",
               "soft": "помірно", "hint": "злегка"}

_КАТ_У_НП = {"hint": 0.25, "soft": 0.5, "default": 0.62, "strong": 0.75,
             "hard": 0.95}


# ── ПІДЛОГА СИЛИ: ОДИН ЧИТАЧ РЕЄСТРУ НА ВЕСЬ ФАЙЛ (Н-outfit-1-089) ──────────
# Константа підлоги в REGISTRY каже про себе: «нижче цієї нормованої сили знахідка не
# видається ВЗАГАЛІ» і що вона «стояла голим літералом у 14 місцях». Заведення
# константи полагодило лише ЧИТАННЯ числа: перевірок лишилось 11, і всі — ПЕРЕД
# емісією, кожна у своїй гілці. Наслідків два, і обидва виміряні:
#   · обіцянку «в усіх гілках емісії» нічим було перевірити — гілку без перевірки
#     видно лише очима, а гілок емісії в цьому файлі десятки;
#   · правило, яке рядка собі не додало, підлоги не мало зовсім (K-CRA-04 виходив
#     вагою 0.0 нарівні з виміряними).
# Тепер підлога — ІНВАРІАНТ ВИХОДУ: гілки емісії її не знають, `обмежити_вагу`
# лише МІТИТЬ підпідлогові знахідки, а викидає їх один фільтр у `review`. Додати
# нову гілку емісії, забувши підлогу, стало неможливо.
def _підлога_нп():
    """Єдине місце, де число підлоги читається з реєстру. Функція, а не модульна
    константа: реєстр — джерело правди в РАНТАЙМІ, і заморожувати його значення
    на момент імпорту означало б завести другий, мовчазний."""
    return C["нп_підлога"]


def _під_підлогою(нп):
    """Чи ця вага нижча за підлогу. `None` і 0.0 — нижчі: «виміру нема» не дає
    права говорити гучніше за виміряне.

    НАПРЯМ ПОРІВНЯННЯ ОДИН НА СИСТЕМУ (`<`, тобто РІВНО підлога — лишається):
    сама `суть` константи описує знайдену розбіжність, коли outfit на рівно 0.05
    знахідку ЛИШАВ, а palette КИДАВ. `palette.py` звіряється з підлогою через
    `>=` проти тієї самої константи — це те саме, що `not _під_підлогою(…)`."""
    return (нп or 0.0) < _підлога_нп()


def _неперервна_сила(сила, вимір=None, поріг=None, розкид=None, повна=None):
    """Система — помічник стиліста: вона МІРЯЄ і віддає силу впливу, а не вирок. Тому
    кожна знахідка мусить нести НЕПЕРЕРВНУ силу, а не бакет.

    Коли є вимір і поріг — сила рахується з маржі (наскільки далеко за поріг), у тій
    самій логіці, якою `_сила` уже знижувала категорію, тільки без округлення в бакет.
    Похибка виміру (`розкид`) гасить силу: рішення тонше за точність не заслуговує ваги.
    Коли виміру нема (твердження категорійне за природою — напр. «нема спільної нитки»),
    сила виводиться з категорії й ЯВНО позначається як не-вимір, щоб не вдавати точність."""
    # ЗНАЙДЕНО ПРИ ПЕРЕВІРЦІ КОДУ ПРОТИ ТЕМИ-1: умова була `not поріг`, тобто ПОРІГ
    # НУЛЬ читався як «порога немає», і правило мовчки падало в категорійний бакет.
    # А нуль — найчастіший законний поріг у цій системі: скрізь, де вимір є ВІДСТАННЮ
    # ВІД ВІКНА («0 = всередині»), поріг дефініційно нульовий. Під це підпадали
    # K-BOD-02 (обидві гілки), K-COMP-01, нічия_стратегія (обидві) — тобто всі
    # зонні правила силуету й уся цільова функція координації видавали 0.5/0.75
    # незалежно від виміру. audit_неперервність цього не бачив, бо жодне з них не
    # входить у його свіп-лист: інваріант «сила з виміру» тримався на семи правилах,
    # які випадково мають ненульовий поріг.
    # Тепер «немає порога» — це `поріг is None`, а нуль — число.
    if вимір is None or поріг is None:
        return _КАТ_У_НП.get(сила, 0.25), "категорія (виміру немає)"
    # При нульовому порозі смуга від нього не виводиться — масштаб мусить бути явним
    # (`повна`). Без нього правило не має права вдавати вимір.
    if not поріг and not повна:
        return _КАТ_У_НП.get(сила, 0.25), ("категорія: поріг 0 і не задано `повна` — "
                                           "масштаб виміру невідомий")
    смуга = abs(поріг) * C["band"] or 1.0
    маржа = abs(float(вимір) - float(поріг))
    # ЗНАЙДЕНО АУДИТОМ audit_неперервність. Раніше масштаб насичення був жорстко
    # `4·смуга = поріг`, тобто сила досягала 1.0 рівно тоді, коли маржа доростала до
    # самого порога. Це прив'язувало РОЗДІЛЬНУ ЗДАТНІСТЬ правила до ВЕЛИЧИНИ його
    # порога, а вона з природним розмахом виміру не пов'язана ніяк. Наслідок виміряний:
    # K-SIL-01 (поріг 0.10, виразність відльотів 0.39–0.50) видавав 1.0 на всіх 38
    # точках прогону — одне значення, тобто бакет, записаний десятковим дробом;
    # K-FIT-01 упирався в стелю на 78% прогону. Тепер масштаб — ЯВНА константа правила
    # (`повна`), яка стоїть у реєстрі зі своїм тіром і калібрується окремо від порога.
    масштаб = float(повна) if повна else смуга * 4.0
    нп = min(1.0, маржа / масштаб)
    if розкид:
        нп *= min(1.0, маржа / max(1e-6, float(розкид)))   # тонше за точність -> гаситься
    # ── МАРЖА РІВНО НА ПОРОЗІ ≠ ВАГА НУЛЬ (Н-outfit-1-089) ────────────────────
    # ЩО ЦЕ ЛОВИТЬ. Умова правила може бути НЕСТРОГОЮ, і тоді перше ж спрацювання
    # стоїть рівно на порозі: K-COL-01 «чотири і більше вагомих рівнів» має
    # `vs["вагомих"] >= 4` при `поріг=4`, тобто при рівно чотирьох маржа нульова,
    # а вага 0.0. Правило емітувалось і тут-таки гинуло під власною підлогою —
    # мовчазна діра рівно в тому випадку, заради якого воно й написане.
    # ЩО СТАЛО. Знахідка, яка дійшла до емісії, несе щонайменше НАЙТИХІШУ ЧУТНУ
    # вагу — саме підлогу, не нуль. Нуль лишається за тими, хто ставить його
    # ЯВНО (`сила_нп=0.0` при емісії: BREAKS правила, архітектурне обмеження) —
    # там це рішення, а не побічний ефект нестрогої нерівності.
    # Той самий прийом уже стояв руками в accessory.K-SHO-07 («вісь вимкнена» →
    # `сила_нп=0.05`); тут він став властивістю шкали, а не звичкою одного автора.
    if маржа == 0.0:
        return _підлога_нп(), ("маржа рівно на порозі %.1f: умова правила нестрога, "
                               "тож вага — підлога, а не нуль" % float(поріг))
    # ── СТЕЛЯ ЗА ОГОЛОШЕНОЮ СИЛОЮ (07.09.2026) ────────────────────────────────
    # ЩО БУЛО НЕ ТАК. Ця гілка віддавала силу З ВИМІРУ й ігнорувала категорію
    # цілком. Тобто оголошена сила правила — головний важіль корпусу («FORCE:
    # hard reject · strong large penalty · default small penalty, overridable ·
    # hint prior only», тема-4 §Як читати) — не доходила до ранжування ЖОДНОГО
    # виміряного правила. Наслідок: `hint`-правило з великою маржею важило в
    # ключі композитора (`sum(сила_нп)`) стільки ж, скільки `hard`. Корпус міг
    # знижувати силу скільки завгодно — на вибір речі це не впливало.
    # ЦЕ ВИЯВИЛОСЬ РІВНО ТОДІ, коли зниження K-COL-06 і K-COL-05 (тема-4, прогін
    # верифікації 2, 05.09.2026) не змінило на реальних образах нічого: обидва
    # правила мають вимір і поріг, тож ішли цією гілкою повз категорію.
    # ЩО СТАЛО. Вимір визначає силу ВСЕРЕДИНІ дозволеного, категорія ставить
    # стелю. `default` — «малий штраф, оборотний» — не може важити як `strong`
    # («великий штраф»), хоч би яка була маржа. Це та сама нерівність «сила ≤
    # верифікація», доведена до останнього числа: доти вона трималась лише на
    # стелі тіру (`_обмежити_тіром`) і на регістрі гейт/репліка, а сама ВАГА
    # лишалась вільною.
    # Неперервність не втрачається: всередині кожної категорії сила лишається
    # неперервною функцією маржі, просто масштабується в її смугу.
    стеля_кат = _КАТ_У_НП.get(сила)
    if стеля_кат is not None and нп > стеля_кат:
        нп = стеля_кат
    return round(max(0.0, min(1.0, нп)), 2), "маржа |%.1f−%.1f| проти масштабу %.3f (%s)%s" % (
        float(вимір), float(поріг), масштаб,
        "явний повна_сила" if повна else "дефолт 4·смуга = поріг",
        (", розкид %.1f" % float(розкид)) if розкид else "")

def обмежити_вагу(знахідки):
    """Оголошена сила правила ставить стелю його вазі в ранзі. Для знахідок із
    БУДЬ-ЯКОГО модуля, а не лише тих, що народились у `_зн`.

    ЧОМУ ЦЕ ОКРЕМА ФУНКЦІЯ, А НЕ ЛИШЕ ГІЛКА В `_неперервна_сила`. Стеля всередині
    `_неперервна_сила` тримає тільки тих, хто прийшов через `_зн` і не переписав
    результат. А переписують: `composer` кладе `dict(O._зн(...), сила_нп=z[...])`
    для K-PAL-16, `accessory` рахує свої числа сам (виміряно 07.09.2026 на живих
    образах: K-WEA-07 `soft` важив 0.95 при стелі категорії 0.50, K-WEA-05
    `strong` — 0.80 при 0.75). Тобто головний важіль корпусу — FORCE — не діяв
    саме там, де знахідка найдорожча.

    ЩО РОБИТЬ. Ріже вагу до стелі категорії й називає це в `сила_нп_джерело`,
    щоб зрізання було видно, а не мовчазне. Нічого не піднімає: слабкий вимір
    лишається слабким.

    «утримано» і «питання» дістають ВАГУ НУЛЬ. Це не косметика: утримана знахідка
    означає «вісь не працює на цьому вході», і додавати за неї 0.25 до суми
    штрафів образу — значить карати річ за те, чого система не знає. K-BOD-05
    після зняття `нога_норма` утримується ЗАВЖДИ, тобто ці 0.25 стояли б рівним
    доданком на кожному образі й нічого не розрізняли.

    І ВАГА, І СЛОВО — В ОДНОМУ МІСЦІ (Н-outfit-1-080). `_гейт_наміром` міняв
    КАТЕГОРІЮ на hint, але не чіпав ні `сила_нп`, ні `впевненість`: знахідка
    виходила вагою 0.5 при стелі hint 0.25 — вдвічі понад стелю власної
    категорії — і зі словом «помірно» від старої сили. Дублювати перерахунок у
    гейті наміру означало б два місця, які розійдуться при першій же зміні; тому
    зрізання ваги й узгодження слова стоять тут, а гейт наміру просто кличе цю
    функцію. Функція ІДЕМПОТЕНТНА за побудовою — ріже ДО стелі, не НА крок, —
    тож подвійне застосування (composer і review) нічого не ріже двічі.

    НА ШЛЯХУ ДО МОДЕЛІ (V10 → Т-03, 12.09.2026). Доти її кликали composer (ключ
    ранжу), review (стани) і pipeline (лише координація) — а вердикт, який їде
    моделі й у журнал, ішов повз: рядки `_доповнення_судді` виходили силою понад
    стелю категорії. Тепер `bridge.від_моделі` кличе її на верхньому рівні, а
    `pipeline.знахідки_вердикту` — на кожному образі; рядкам `для_стиліста` для
    цього повернуто `сила` (категорію), без якої стелі нема за що брати.
    """
    for z in знахідки or []:
        с = z.get("сила")
        if с in ("утримано", "питання"):
            if z.get("сила_нп"):
                z["сила_нп_джерело"] = ("вага знята: сила «%s» — це відсутність входу, "
                                        "не вердикт над річчю" % с)
            z["сила_нп"] = 0.0
            continue
        стеля = _КАТ_У_НП.get(с)
        нп = z.get("сила_нп")
        if стеля is not None and нп is not None and нп > стеля:
            z["сила_нп_джерело"] = ("%s → зрізано до стелі категорії «%s» = %.2f "
                                    "(сила ≤ верифікація)"
                                    % (z.get("сила_нп_джерело") or "вимір", с, стеля))
            z["сила_нп"] = стеля
        _узгодити_слово(z)
        # ── МІТКА, А НЕ ВИКИД (Н-outfit-1-089) ────────────────────────────────
        # Хто рахує вагу, той не вирішує долю знахідки: `обмежити_вагу` кличуть і
        # composer, і pipeline, і review, і жоден із них не має права мовчки
        # прорідити чужий список. Тому підлога тут лише НАЗИВАЄТЬСЯ, а викидає
        # один читач — `review` на виході стану. Блокер підлозі не підлеглий:
        # «правило-гейт порушене» — це не про силу властивості.
        # Мітка службова й до виходу не доїжджає: фільтр `review` знімає її разом
        # зі знахідкою, а тим, хто лишився, її не ставлять.
        # ДРУГИЙ ВИНЯТОК — ПРАВИЛО, ЯКОМУ КОРПУС ПРИПИСАВ ВАГУ 0.0
        # (`ВАГА_НУЛЬ_ЗА_КОРПУСОМ`, 18.09.2026). Підлога існує, щоб не випускати
        # СЛАБКУ ДУМКУ: її власна `суть` у реєстрі каже «нижче цієї нормованої
        # сили знахідка не видається взагалі». K-COL-JOIN думки не несе зовсім —
        # він несе ЗЛИТИЙ ЗАПИТ У КАТАЛОГ, і вага 0.0 в нього не від слабкості
        # виміру, а з корпусу дослівно: «FORCE: вага 0.0 — ранг не змінюється
        # взагалі. У каталог іде ОДНЕ спільне вікно замість двох окремих
        # запитів». Тобто підлога міряла його не тією міркою, якою він
        # оголошений, і викидала разом із єдиним, заради чого він є.
        if (_під_підлогою(z.get("сила_нп")) and not z.get("блокує")
                and z.get("правило") not in ВАГА_НУЛЬ_ЗА_КОРПУСОМ):
            z["під_підлогою"] = True
    return знахідки


def _узгодити_слово(z):
    """Слово знахідки йде за її СИЛОЮ, не за тією, з якою вона народилась.

    `впевненість` і `для_стиліста` ставить `_зн` у мить народження. Хто потім
    міняє категорію (гейт наміру, стеля тіру, обмеження осі), лишав старе слово:
    знахідка казала «помірно», маючи силу hint. Репліку перебудовуємо з `суть` і
    `чому`, бо `суть` дописується хвостом («— за цього наміру не порушення, а
    облік»), а `_репліка` бере частину ДО « — » і хвіст у текст не тягне.
    Знахідки без `впевненість` (гейти й питання) не чіпаємо: у них слова нема."""
    с = z.get("сила")
    if "впевненість" not in z or с not in ВПЕВНЕНІСТЬ:
        return z
    if z["впевненість"] != ВПЕВНЕНІСТЬ[с]:
        z["впевненість"] = ВПЕВНЕНІСТЬ[с]
        if z.get("суть") is not None and z.get("чому") is not None:
            z["для_стиліста"] = _репліка(z["суть"], z["чому"])
    return z


def _зн(правило, сила, суть, речі, чому, ремонт=None, запит=None, ламається=None,
        поріг=None, примітка=None, вимір=None, розкид=None, повна=None,
        reg=None, діагностика=None):
    """ЄДИНИЙ конструктор знахідки. Форма виходу оголошена в `протокол.ЗНАХІДКА`.

    `рег_карту` знято Н-02-05: регістр рахує `регістр()` з однієї таблиці, і
    підсунути йому свою карту більше нікому. Викликач, який хоче іншого регістру,
    міняє рядок у `ПОЛІТИКА_РЕГІСТРУ` — там, де поруч стоїть `джерело`."""
    # ПОРЯДОК ДВОХ СТЕЛЬ ЗНАЧУЩИЙ, І ВІН ВИМІРЯНИЙ (13.09.2026). Спершу тір, потім
    # корпус. Навпаки — та сама кінцева сила, але інша НОТА: на K-WEA-05/06 і
    # K-FIT-01 стеля тіру нижча за стелю корпусу, тож «корпус першим» забирав би в
    # знахідки правдиве пояснення («стоїть на константі тіру T3») і підставляв
    # слабше («стільки дає корпус»), хоча зрізав саме тір. Так само корпусна стеля
    # лишається ЖИВОЮ, а не декоративною: щойно під правилом оголосять сильнішу
    # константу — тір пропустить, і сила впреться в те, що каже корпус.
    _заявлена = сила            # з чим покликав емітент — для ноти другої стелі
    сила, _тір_нота = _обмежити_тіром(правило, сила, reg)
    сила, _корп_нота = _обмежити_корпусом(правило, сила, заявлена=_заявлена)
    рег = регістр(правило, сила, reg)
    d = dict(правило=правило, сила=сила, регістр=рег, суть=суть, речі=речі, чому=чому)
    d["сила_нп"], d["сила_нп_джерело"] = _неперервна_сила(сила, вимір, поріг, розкид, повна)
    if рег == "репліка":
        # знахідка не блокує: несе впевненість замість сили заборони й промовляльне «як»
        d["впевненість"] = ВПЕВНЕНІСТЬ.get(сила, "злегка")
        d["для_стиліста"] = _репліка(суть, чому)
        d["блокує"] = False
    else:
        # ЗНАЙДЕНО ПРИ ПІДКЛЮЧЕННІ ПОСАДКИ: блокує=True ставилось усьому, що не репліка,
        # тобто й регістру «питання». Питання нічого не забороняє — воно каже, що входу
        # нема. Тут це не вилазило лише тому, що review() фільтрує блокери ще й за силою
        # ("hard"/"strong"), а в питання сила "питання"; тобто помилка була латентна й
        # чекала першого викликача, який читає поле напряму.
        d["блокує"] = (рег == "гейт")
    # ЗНЯТИЙ ГЕЙТ НАЗИВАЄ СЕБЕ. Інакше правка Н-V23-046 зробила б рівно те, чим
    # хвора система, яку вона лікує: тихо змінила б вердикт і нікому не сказала.
    if _гейт_без_доказу(правило, сила, reg):
        d["гейт_знято"] = ГЕЙТ_БЕЗ_ДОКАЗУ
    if ремонт: d["ремонт"] = ремонт if d.get("блокує", True) else _мʼякший_ремонт(ремонт)
    # запит без жодного числового вікна чи сім'ї — не фільтр, а шум для шару retrieval
    if запит and any(k for k in запит if k not in ("слот", "чому", "замість")):
        d["запит_у_каталог"] = запит
    if ламається: d["де_ламається"] = ламається
    if _корп_нота: d["стеля_корпусу"] = _корп_нота
    if _тір_нота: d["стеля_тіру"] = _тір_нота
    if поріг is not None:
        _т = _тір_правила(правило, reg)
        d["поріг"] = dict(значення=поріг, тір=_т,
                          статус=("виміряний стандарт" if _т == "T1" else
                                  "структура з дослідження" if _т == "T2" else
                                  "фольклорна константа, не калібрована"))
    if примітка: d["примітка"] = примітка
    # `діагностика` — числа для РОЗРОБНИКА, які не мають права піти в текст людині:
    # метрики тіла (WHR, перекос, обхвати). Окреме поле, бо мовний гейт і контракт
    # виходу перевіряють `суть`/`чому`/`ремонт`, а не його.
    if діагностика: d["діагностика"] = діагностика
    # Правило, якого нема в реєстрі корпусу, більше не виходить мовчки нарівні з
    # рештою: знахідка сама несе, що під нею запису корпусу немає.
    # СУФІКСНИЙ ВАРІАНТ ПИТАЄ ЗА СВОЮ БАЗУ: варіант правила — це те саме правило,
    # і власного запису в корпусі він не має й мати не може.
    _база = ІП.база(str(правило)) or str(правило)
    _пк = ПОЗА_КОРПУСОМ.get(_база)
    if _пк:
        d["поза_корпусом"] = _пк
        d["чому"] = d["чому"] + (" ⚠ ПРАВИЛО ПОЗА КОРПУСОМ: %s" % _пк)
    # ТРЕТІЙ СТАН СЮДИ НЕ ЙДЕ, І ЦЕ РІШЕННЯ, А НЕ ПРОПУСК. «Тема називає, але
    # форми означення не розпізнано» — не те саме, що «жодна тема не називає»;
    # зливати їх в одне попередження означало б назвати вироком те, що є
    # питанням (розпізнавач некалібрований). Таблиця третього стану лежить у
    # `rule_genus`, а не тут: її ключі — правила КОРПУСУ, і в модулі ядра вони
    # зарахувались би за «у виконуваному коді», тобто бухгалтерія про дірку
    # закривала б дірку. Читає її `audit_contracts` розділом «ПИТАННЯ».
    return d


# ── БЛОК НАМІРУ ПЕРЕЇХАВ СЮДИ (Н-02-01, сесія 2) ────────────────────────────
# Стояв в `outfit.py` з міркування «намір — властивість суду над образом, а не
# ваги» (сесія 1). Коли колір поїхав у `колір_образу.py`, виявилось, що
# споживачі стоять ПО ОБИДВА БОКИ розділу: `_гейт_наміром` тримає пʼять
# рахункових колірних знахідок, `_намір` і `_канон_намір` — судові `review` та
# `підлога_інтересу_проактивно`. Спільний модуль у них один, цей; а сам гейт і
# так кличе `обмежити_вагу` двадцятьма рядками вище. Код не змінено.
# ─────────────────────────── НАМІР (INTENT) ───────────────────────────
# Корпус: «Всі мапи умовні на intent». Перша версія цього не мала — і рахункові
# правила (≤3 сім'ї, ≤2 гучних, сирота-акцент, 4+ рівнів) звучали як універсальні
# істини. Для maximalism / fashion-editorial / авангарду це хибно: там надлишок —
# і є хід. Тому рахункові правила гейтуються наміром, а МЕХАНІЗМОВІ — ні.
#
# Чому саме такий поділ. Рахункове правило («не більше N») спирається на конвенцію
# повсякденної читабельності; змінюється намір — змінюється конвенція.
# Механізмове правило описує оптичну подію, яка стається незалежно від наміру:
# дві нейтралі на одній світлоті з великим ΔE00 виглядають як промах фарбування;
# стрибок біля обличчя стирає обличчя. Намір може зробити це БАЖАНИМ, тож знахідка
# лишається, але як факт, не як заборона — сила падає, формулювання змінюється.
# ОДНА ФОРМА ЗАПИСУ НАМІРУ (Н-outfit-1-078). Ключі тут стояли через дефіс
# («fashion-forward»), а bridge, composer, fit, brief і сам outfit подають
# підкреслення («fashion_forward»). Отже на ЖИВОМУ вході гейт наміру ключа не
# знаходив, мовчки вважав намір невідомим і застосовував conventional: рахункові
# ліміти діяли рівно там, де намір їх скасовує. Канонічна форма — підкреслення
# (нею говорить уся решта системи); дефісна форма зі старих викликачів лягає
# туди ж через `_канон_намір`, а не додається другим ключем.
def _канон_намір(x):
    """Канон значення наміру: підкреслення, нижній регістр, без країв."""
    return str(x or "conventional").strip().lower().replace("-", "_")

INTENT = {
 "conventional": dict(рахункові=1.0, підпис=""),
 "fashion_forward": dict(рахункові=0.0,
     підпис="намір fashion_forward: надлишок рахується як хід, не як провал"),
 "editorial": dict(рахункові=0.0,
     підпис="намір editorial: рахункові ліміти не застосовуються"),
 # РІШЕННЯ ПРО «statement» (Н-outfit-1-078, крок 5): намір ВІДОМИЙ, рахункові
 # ліміти ДІЮТЬ. Підстава — не мовчання, а два виміри. (1) Корпус: тема-12:384
 # «patterned statement socks are a declared accent and SPEND the chroma budget»
 # — під statement бюджет не скасовується, він витрачається свідомо; тема-2:1858
 # дозволяє K-PAL-12 «only under statement intent», тобто корпус цей намір знає
 # поіменно. (2) Код: `pipeline.py:1989` під statement уже ПОЛОВИНИТЬ силу
 # знахідок про конфлікт хром, а не знімає їх, — пом'якшення вже зроблено нижче
 # по ланцюгу, і дублювати його тут означало б зрізати двічі. Тому підпис
 # порожній, як у conventional: різниця між ними живе в pipeline, не тут.
 # Чому не «лишити невідомим»: `bridge.py:1115` оголошує statement кнопкою
 # стенда, а `composer.СМІЛИВІ_НАМІРИ` і `суд_образу.блиск_бюджет` знають його
 # поіменно — попередження «модулю невідомий» на кожному прогоні живої кнопки
 # було б неправдою про власний стан.
 "statement": dict(рахункові=1.0, підпис=""),
}
def _намір(intent):
    """Невідомий намір не вдає із себе conventional мовчки: корпус має граматику для
    гранжу/стрітвіру, але не має лексикону, і про це має знати той, хто читає вихід."""
    сирий = intent
    intent = _канон_намір(intent)
    if intent not in INTENT:
        return dict(INTENT["conventional"],
                    підпис=f"намір «{сирий}» модулю невідомий — застосовано conventional; "
                           "рахункові ліміти можуть бути хибними для цього напряму")
    return INTENT[intent]

def _гейт_наміром(зн, intent):
    """Рахункова знахідка за нестандартного наміру не зникає — вона стає обліком."""
    n = _намір(intent)
    if n["рахункові"] >= 1.0: return зн
    зн = dict(зн, сила="hint", намір=n["підпис"])
    зн["суть"] = зн["суть"] + " — за цього наміру не порушення, а облік"
    зн.pop("запит_у_каталог", None)
    # Категорія змінилась — вага і слово мають піти за нею. Не дублюємо тут
    # перерахунок, а віддаємо єдиному місцю (Н-outfit-1-080).
    return обмежити_вагу([зн])[0]
