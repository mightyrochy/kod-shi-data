def _норм_тір(t):
    """Тір -> клас доказу, або None для дефініційних. Невідомий рядок — найслабший
    клас, і це навмисно: незнайомий тір не має права давати правилу більше прав."""
    return _ТІР_НОРМА.get(t, "T3")

def _за_кого(v):
    """ID правил, за які голосує константа реєстру. Приймає обидві форми поля
    «прав» — список (канон) і одиночний рядок (реєстри інших модулів), — щоб
    машинерія інваріанта лишалась одна на всі реєстри. Службова константа
    (`службова=True`, поля «прав» нема) не голосує ні за кого."""
    п = v.get("прав")
    if п is None: return ()
    return tuple(п) if isinstance(п, (list, tuple, set)) else (п,)

def _тір_правила(правило, reg=None):
    """`reg` — реєстр констант. Параметр доданий, щоб інший модуль правил (посадка.py)
    проганяв СВОЇ константи через ЦЮ саму машинерію інваріанта, а не копіював її:
    копія розійшлась би з оригіналом при першій же зміні, і «сила ≤ верифікація»
    трималась би у двох місцях по-різному."""
    reg = REGISTRY if reg is None else reg
    тіри = [_норм_тір(v.get("t")) for v in reg.values() if правило in _за_кого(v)]
    тіри = [t for t in тіри if t]        # дефініційні константи не голосують
    if not тіри: return None
    return min(тіри, key=lambda t: ("T1", "T2", "T3").index(t) * -1)   # найслабший

def стеля_сили(правило, reg=None):
    """Максимальна сила, на яку правило має право за своєю доказовою базою."""
    т = _тір_правила(правило, reg)
    return СТЕЛЯ_ЗА_ТІРОМ.get(т) if т else None

