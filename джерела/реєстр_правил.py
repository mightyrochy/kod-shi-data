def регістр(правило, сила, рег_карта=None, reg=None):
    # РЕГІСТР БУВ СУТО ПО-ПРАВИЛЬНИЙ, і це втрачало один випадок: правило працює, а
    # ВХОДУ під конкретну річ немає. «Питання» — властивість ВИКЛИКУ, не правила:
    # K-BOD-02 має вхід на полотні й не має його, коли тканина не відома. Доти таке
    # спрацювання виходило реплікою, тобто НЕВІДРІЗНЯЛЬНО від виміряного вердикту, і
    # стиліст не бачив, що під ним бракує входу. Сила «питання» тепер сама себе несе.
    if сила == "питання": return "питання"
    р = (РЕГІСТР_ПРАВИЛА if рег_карта is None else рег_карта).get(правило, "репліка")
    # `reg` — реєстр констант модуля, з якого прийшла знахідка (той самий параметр,
    # що вже ходить у `_обмежити_тіром`). Без нього стеля рахувалась би по REGISTRY
    # ядра, і правило accessory/outer щоразу виглядало б беззаконним.
    _ст = стеля_сили(правило, reg)
    if р == "гейт" and сила in ("hard", "strong") and _ст in ("hard", "strong"): return "гейт"
    if р == "гейт": return "репліка"      # слабка знахідка навіть механічного правила лише промовляється
    return р

