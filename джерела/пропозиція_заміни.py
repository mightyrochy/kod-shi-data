# -*- coding: utf-8 -*-
"""Пропозиція зі складу добору: межі, явний вибір і повторний суд цілого образу."""
from copy import deepcopy
from itertools import combinations, product
import json

import знахідка as ЗН


def варіанти(образ, пули):
    """Видає склади з однією, потім кількома замінами з готових пулів добору.

    Правило не задає кандидатів. Порядок усередині пулу лишається за добором;
    кількість зауважень або їхня сума порядку не визначає.
    """
    місця = [н for н, річ in enumerate(образ) if пули.get(річ["id"])]
    for кількість in range(1, len(місця) + 1):
        for позиції in combinations(місця, кількість):
            for набір in product(*(пули[образ[н]["id"]] for н in позиції)):
                новий = list(образ)
                for н, річ in zip(позиції, набір):
                    новий[н] = річ
                if len({р["id"] for р in новий}) == len(новий):
                    yield новий


def _зауваження(вердикт):
    """Дає змістовні зауваження з усього дерева суду разом зі станом/шляхом."""
    return [(шлях, з) for шлях, з in ЗН.усі(вердикт)
            if з.get("полярність") != "опора" and not з.get("тінь")
            and (з.get("блокує") or (з.get("сила_нп") or 0) > 0)]


def _непевні(вердикт):
    """Дає правила, які не одержали входу, щоб заміна не приховала перевірку."""
    return [(ш, з) for ш, з in ЗН.усі(вердикт)
            if з.get("без_входу") or з.get("сила") in ("питання", "утримано")]


def _ключ(шлях, знахідка, наступність=None):
    """Зберігає правило, стан і учасників з відповідністю старої та нової речі.

    Та сама властивість на наступниці речі не є новою вадою. Перехід на іншу
    позицію образу лишається іншим ключем; вихідне правило перевіряється окремо
    на всіх речах, навіть якщо його сила зменшилась.
    """
    наступність = наступність or {}

    def привести(значення):
        """Повертає учасників у вихідних id, незалежно від порядку переліку."""
        if isinstance(значення, str):
            return наступність.get(значення, значення)
        if isinstance(значення, dict):
            return {к: привести(в) for к, в in значення.items()}
        if isinstance(значення, (list, tuple)):
            return sorted((привести(в) for в in значення), key=lambda в: json.dumps(в, sort_keys=True))
        return значення

    учасники = знахідка.get("учасники") or знахідка.get("речі") or []
    return (шлях, знахідка.get("правило"), знахідка.get("бік"),
            json.dumps(привести(учасники), ensure_ascii=True, sort_keys=True))


def _у_межах(новий, образ, межі, явний_вибір):
    """Звіряє повні записи пулу й незмінність названих жінкою речей.

    `межі` — записи, уже відібрані добором у сценарії запиту; в оцінці це
    лише її речі. Самого збігу id недостатньо: поля кандидата теж мають збігтись.
    `явний_вибір` — id речей, які вона попросила зберегти; колір і гаму добір
    застосовує до пулу до виклику цієї функції.
    """
    if len(новий) != len(образ) or len({р.get("id") for р in новий}) != len(новий):
        return False
    за_ід = {р["id"]: р for р in образ}
    if not set(явний_вибір) <= за_ід.keys():
        return False
    for стара, річ in zip(образ, новий):
        if річ.get("слот") != стара.get("слот"):
            return False
        if річ != за_ід.get(річ.get("id")) and річ != межі.get(річ.get("id")):
            return False
    нові_за_ід = {р["id"]: р for р in новий}
    return all(нові_за_ід.get(ід) == за_ід[ід] for ід in явний_вибір)


def перевірити_кроками(образ, зауваження, кандидати, межі, явний_вибір, суддя, база):
    """Повертає перевірений склад із замінами або пояснення без заміни.

    Повний суд викликається на копії саме запропонованого складу. Вихідна
    сім'я зауважень мусить зникнути всюди, а інші зауваження не можуть перейти
    на інші позиції образу чи посилитись. Уже відомі зауваження лишаються інформацією,
    без підрахунку балів. Брак входу замість вихідної перевірки не є успіхом.
    """
    правила = {з["правило"] for з in зауваження}
    if not правила:
        raise ValueError("Для пропозиції потрібне вихідне зауваження")
    до = {_ключ(ш, з): з for ш, з in _зауваження(база)}
    непевні_до = {_ключ(ш, з) for ш, з in _непевні(база)}
    for новий in кандидати:
        if not _у_межах(новий, образ, межі, явний_вибір) or новий == образ:
            continue
        зміни = [dict(було=с["id"], стало=н["id"])
                 for с, н in zip(образ, новий) if с != н]
        наступність = {з["стало"]: з["було"] for з in зміни}
        вердикт = суддя(deepcopy(новий))
        yield
        if not isinstance(вердикт, dict) or not isinstance(вердикт.get("знахідки"), list):
            raise ValueError("Суд заміни не повернув повного вердикту зі знахідками")
        if вердикт.get("помилка"):
            raise ValueError("Суд заміни повернув помилку")
        всі = ЗН.список(вердикт)
        if any(з.get("правило") in правила and
               (з.get("без_входу") or з.get("сила") in ("питання", "утримано")) for з in всі):
            continue
        if any(_ключ(ш, з, наступність) not in непевні_до for ш, з in _непевні(вердикт)):
            continue
        після = _зауваження(вердикт)
        if any(з.get("правило") in правила for _, з in після):
            continue
        if вердикт.get("блокує") and вердикт.get("блокує") != база.get("блокує"):
            continue
        if any(_ключ(ш, з, наступність) not in до or
               float(з.get("сила_нп") or 0) > float(до[_ключ(ш, з, наступність)].get("сила_нп") or 0) or
               (з.get("блокує") and not до[_ключ(ш, з, наступність)].get("блокує")) for ш, з in після):
            continue
        return dict(образ=deepcopy(новий), заміни=зміни, вердикт=вердикт, пояснення=None)
    return dict(образ=None, заміни=[], вердикт=None,
                пояснення="У межах запиту немає перевіреної зміни, що усуває цю причину "
                          "без нового зауваження до образу; склад лишається твоїм вибором.")


def перевірити(*аргументи, **поля):
    """Доводить покроковий добір до кінця для синхронного викликача."""
    кроки = перевірити_кроками(*аргументи, **поля)
    while True:
        try:
            next(кроки)
        except StopIteration as кінець:
            return кінець.value
