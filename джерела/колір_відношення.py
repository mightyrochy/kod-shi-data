# ЩО БУЛО. Дуга сім'ї очей (K-PAL-02/13, `palettes._дуги_сімей`) — тон очей ±30° CIELAB, суд — ще й із
# запасом 10° CIELAB (`колір_річ.у_дугах_меж`). 30° CIELAB — це ±18° кола художника в синіх і ±53° у карих:
# карі очі «відлунювали» гірчицею, а блакитні не відлунювали волошковою сукнею.
# ЩО СТАЛО. Дуга — вікно на колі художника (`colorspace.дуга_кола`: образ дуги кола в CIELAB, щоб її несли
# ті самі поля), а «тон у дузі» — сила, як у класів тону вище: відстань тону до центру дуги на колі у
# вікні її пів-ширини, межа розмита `СІГМА_МЕЖІ`, плюс вікно ΔH* практиків (K-COL-11) у тій самій пропорції,
# що `ВІКНА_ΔH` до `ВІКНА_ТОНУ` (3 до 15°): дуга ±30° кола приймає й |ΔH*| ≤ 6 до центру — у приглушених і
# бурих тон, який око бачить тим самим. Зріз — 0.5 (межа дуги); суд, що не звинувачує річ на краю, може
# брати кінець згасання `КІНЕЦЬ_ЗГАСАННЯ` (1.645·σ = 8° кола за межею) замість запасу CIELAB.
# ДЕ ЛАМАЄТЬСЯ. ΔH* до центру дуги рахується хромою речі (центр — тон без хроми), як `palettes._тон_поруч`.
# Певність тону сили не множить: дугою правила судять лише речі, які самі визнали кольоровими. Ролі схем
# (±15° кола) цим вікном очима хиблять у бурих і темних (рядок 4780) — тому їхні дуги лишились CIELAB.
КІНЕЦЬ_ЗГАСАННЯ = 0.05  # сила, нижче якої тон поза вікном без сумніву (тіло #795: «поза» ≤ 0.05)


def сила_в_дузі(р, дуга):
    """(мін, макс) сили «тон запису р лежить у дузі тону» — дуга (lo, hi) CIELAB з обходом 0°, судиться на
    колі художника: центр і пів-ширина — кінці дуги на колі; сила — `у_вікні` відстані тону до центру з
    розмиттям `СІГМА_МЕЖІ`, об'єднана з вікном ΔH* пів-ширини · 3/15 (шапка розділу). Запис —
    `колір_річ.запис_кольору`; вікно слова — межі сили по всій його дузі (точки дуги судить викличник,
    `колір_річ.у_дугах_меж`). Запису чи тону нема — `НЕВІДОМО`."""
    if р is None or р["коло"] is None:
        return НЕВІДОМО
    к0 = у_коло_художника(float(дуга[0]))
    пів = ((у_коло_художника(float(дуга[1])) - к0) % 360.0) / 2.0
    кц = (к0 + пів) % 360.0
    hц = з_кола_художника(кц)
    рк = _розкид_дуг(р["коло"], (кц, кц))
    return _диск(рк, _дельта_h(р, dict(р, дуга=(hц, hц))), пів, пів * ВІКНА_ΔH["same_hue"][0] / ДУГА_ВІДЛУННЯ)


# Сім'я очей — відлуння райдужки, а не будь-яка аналогова гармонія.
# Корпус: тема-2 §6.1, R-COL-17, K-PAL-02; K-PAL-01 (тепла синя —
# бірюза/петроль, холодна — кобальт/барвінок/нейві); тема-4 K-COL-11/12.
# Усі межі нижче — T3, практикова оцінка, НЕ результат Perrett чи калібрування.
РЕЄСТР_ОЧЕЙ = {
    "families": dict(t="T3", val=((330., 30.), (15., 90.), (90., 140.),
                                (135., 205.), (205., 235.), (235., 285.), (275., 335.)),
                     прав=["K-PAL-02", "K-PAL-13"], джерело="K-PAL-01: температурні сім'ї; межі на колі художника"),
    "chroma": dict(t="T3", val=18., прав=["K-PAL-02", "R-COL-17"],
                   джерело="приглушена райдужка не повторюється чистою барвою; межа між м'якими й барвними очима"),
    "chroma_gap": dict(t="T3", val=8., прав=["K-PAL-02", "K-COL-12"],
                       джерело="відлуння приглушеного кольору: запас C*, не відношення хром тінту й відтінку"),
    "value": dict(t="T3", val=(-25., 30.), прав=["K-PAL-02", "K-COL-12"],
                  джерело="відлуння зберігає світлоту; світлий тінт допустимий ширше темного"),
    "shade": dict(t="T3", val=(-40., 30.), прав=["K-PAL-02", "K-COL-11"],
                  джерело="барвна райдужка: відтінки однієї температурної сім'ї, зокрема блакитний — кобальт"),
}


def _зсув_осі(ра, рб, вісь):
    """Межі різниці осі кольору речі й райдужки; працює також із вікнами слів."""
    return (ра[вісь][0] - рб[вісь][1], ра[вісь][1] - рб[вісь][0])


def _смуга_сили(р, межі, сигма):
    """Межі сили належності інтервалу р лінійній смузі з плавними краями."""
    lo, hi = межі
    сила = lambda x: _ф(x - lo, сигма * math.sqrt(2.0)) - _ф(x - hi, сигма * math.sqrt(2.0))
    ц = (lo + hi) / 2.0
    return (min(сила(р[0]), сила(р[1])), сила(min(max(ц, р[0]), р[1])))


def _сім_я_на_колі(р, дуга):
    """Межі сили належності запису кольору температурній сім'ї на колі художника."""
    lo, hi = дуга
    пів = ((hi - lo) % 360.0) / 2.0
    ц = (lo + пів) % 360.0
    return _у_вікні_меж(_розкид_дуг(р["коло"], (ц, ц)), (0., пів, False), СІГМА_МЕЖІ)


def сила_сім_ї_очей(р, очі):
    """Межі сили відлуння кольору райдужки: тон, підтон, хрома й світлота, зріз 0.5.

    Приглушене відлуння бере спільне вікно тону (коло + ΔH*), але зберігає
    хрому й світлоту. Барвне — тінти й відтінки однієї температурної сім'ї
    кола: кобальт лишається синім, бірюза не стає холодним синім. Це два
    плавні вікна одного кодування, без нових кутів CIELAB і без читання слів.
    Нема райдужки чи тону — невідомо; відсутні осі не підміняються дефолтом.
    """
    if р is None or очі is None or р["коло"] is None or очі["коло"] is None:
        return НЕВІДОМО
    пів = RELATIONS["analogous"][1]
    тон = _диск(_розкид_дуг(р["коло"], очі["коло"]), _дельта_h(р, очі),
                пів, пів * ВІКНА_ΔH["same_hue"][0] / ДУГА_ВІДЛУННЯ)
    # Кінець згасання старої дуги зберігається лише для приглушеного відлуння.
    тон = tuple(min(1., с / (2. * КІНЕЦЬ_ЗГАСАННЯ)) for с in тон)
    дL, дC = _зсув_осі(р, очі, "L"), _зсув_осі(р, очі, "C")
    хрома = РЕЄСТР_ОЧЕЙ["chroma_gap"]["val"]
    м_яке = _мінімум(тон, _смуга_сили(дL, РЕЄСТР_ОЧЕЙ["value"]["val"], СІГМА_СВІТЛОТИ),
                      tuple(_ф(хрома - д, СІГМА_ΔH * math.sqrt(2.)) for д in (дC[1], дC[0])))
    сс = [_мінімум(_сім_я_на_колі(р, д), _сім_я_на_колі(очі, д)) for д in РЕЄСТР_ОЧЕЙ["families"]["val"]]
    сім = (max(с[0] for с in сс), max(с[1] for с in сс))
    барвне = _мінімум(сім, _смуга_сили(дL, РЕЄСТР_ОЧЕЙ["shade"]["val"], СІГМА_СВІТЛОТИ),
                        tuple(_ф(Cc - РЕЄСТР_ОЧЕЙ["chroma"]["val"], СІГМА_ΔH * math.sqrt(2.)) for Cc in очі["C"]))
    return (max(м_яке[0], барвне[0]), max(м_яке[1], барвне[1]))
