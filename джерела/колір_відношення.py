def _ф(x, s):
    """Нормальна функція розподілу в точці x при масштабі s = σ·√2."""
    return 0.5 * (1.0 + math.erf(x / s))


def у_вікні(d, вікно, сигма):
    """Імовірність, що справжня відстань тонів на колі лежить у `вікно` (від, до, відкрита), коли
    виміряна — d (0…180°), а знак і зсув різниці розмиті гаусом σ (σ = 0 — тверда межа).

    Чому так: різниця тонів зі знаком δ ~ N(d, σ), а відстань — |δ|, згорнута на колі, тож вікну
    [a, b] відповідають відрізки [a, b] і [−b, −a] з кроком 360°; при σ → ∞ сила прямує до частки
    кола під вікном (той самий сектор — 1/12)."""
    a, b, відкрита = вікно
    if сигма <= 0.0:
        return 1.0 if ((d > a) if відкрита else (d >= a)) and d <= b else 0.0
    s, p = сигма * math.sqrt(2.0), 0.0
    for м in (-720.0, -360.0, 0.0, 360.0, 720.0):
        p += _ф(b + м - d, s) - _ф(a + м - d, s) + _ф(-a + м - d, s) - _ф(-b + м - d, s)
    return min(1.0, max(0.0, p))


def _у_вікні_меж(р, вікно, сигма):
    """(мін, макс) `у_вікні` для відстані з інтервалу р = (мін, макс): сила одногорба з вершиною в
    центрі вікна (0 — для вікна від нуля, 180 — для вікна до 180), тож мінімум — на кінці інтервалу,
    максимум — у найближчій до центру точці."""
    a, b, _ = вікно
    ц = 0.0 if a == 0.0 else 180.0 if b == 180.0 else (a + b) / 2.0
    return (min(у_вікні(р[0], вікно, сигма), у_вікні(р[1], вікно, сигма)),
            у_вікні(min(max(ц, р[0]), р[1]), вікно, сигма))


def _дельта_h(ма, мб):
    """(мін, макс) різниці тону ΔH* = 2·√(C1·C2)·sin(Δh/2) (CIE; Ou–Luo, CIEDE2000) між двома
    `межі_кольору`: ΔH* росте з обома хромами й з Δh на 0…180°, тож межі — кути (C0, Δh мін) і
    (C1, Δh макс). Ахроматичне слово (дуга None) — Δh будь-який."""
    р = _КР._розкид_дуг(ма[4], мб[4])
    s = lambda c1, c2, д: 2.0 * math.sqrt(max(c1, 0.0) * max(c2, 0.0)) * math.sin(math.radians(д) / 2.0)
    return (s(ма[2], мб[2], р[0]), s(ма[3], мб[3], р[1]))


def _ближній_тон(a, b, клас, р_кола):
    """(мін, макс) сили ближнього класу тону (K-COL-11): об'єднання сектора кола художника (Р2а) і вікна
    різниці тону ΔH* практиків (`ВІКНА_ΔH`); кільце (сусідній, аналоговий) — зовнішній диск мінус «той самий».
    Вікно ΔH* гасне за `МЕЖА_БЛИЗЬКИХ` кола. Певність тону множить `сила`."""
    дh = _дельта_h(_КР.межі_кольору(a), _КР.межі_кольору(b))
    чв = [у_вікні(d, (0.0, МЕЖА_БЛИЗЬКИХ, False), СІГМА_МЕЖІ) for d in (р_кола[1], р_кола[0])]

    def диск(к_кола, к_ΔH):
        """Сила «відстань тону — від нуля до межі» за колом чи за ΔH*, що більша (обидві спадні)."""
        к = _у_вікні_меж(р_кола, (0.0, ВІКНА_ТОНУ[к_кола][1], False), СІГМА_МЕЖІ)
        м = ВІКНА_ΔH[к_ΔH][0]
        н = (у_вікні(дh[1], (0.0, м, False), СІГМА_ΔH) * чв[0], у_вікні(дh[0], (0.0, м, False), СІГМА_ΔH) * чв[1])
        return (max(к[0], н[0]), max(к[1], н[1]))

    зовн, мінус = диск(клас, клас), ВІКНА_ΔH[клас][1]
    if мінус is None:
        return зовн
    вн = диск(мінус, мінус)
    return (max(0.0, зовн[0] - вн[1]), min(1.0, max(0.0, зовн[1] - вн[0])))


def певність_тону(x):
    """(мін, макс) певності τ, що колір має тон: ворота хроми й світлоти (Ou–Luo E_C, O'Donovan);
    None — кольору нема. Обидві ворота зростають, тож межі — кути вікна (C0·L0, C1·L1)."""
    м = _КР.межі_кольору(x)
    if м is None:
        return None
    в = lambda v, ц: 0.5 + 0.5 * math.tanh(КРУТІСТЬ_ТОНУ * (v - ц))
    return (в(м[2], ХРОМА_ТОНУ) * в(м[0], СВІТЛОТА_ТОНУ), в(м[3], ХРОМА_ТОНУ) * в(м[1], СВІТЛОТА_ТОНУ))


def _добуток(*мм):
    """Добуток інтервалів сили (усі в 0…1): нижня межа — добуток нижніх, верхня — верхніх."""
    lo, hi = 1.0, 1.0
    for м in мм:
        lo, hi = lo * м[0], hi * м[1]
    return (lo, hi)


def _гучна(x):
    """Гучність кольору (C* ≥ `hi_C`) інтервалом сили: «так» — (1, 1), «ні» — (0, 0), інакше
    невідомо. Гучність — властивість однієї речі (K-COL-02), її межу судить `колір_річ.гучність_меж`."""
    return {"так": (1.0, 1.0), "ні": (0.0, 0.0)}.get(_КР.гучність_меж(x), НЕВІДОМО)


def _крок_світлоти(ра, рб, поріг, сигма):
    """(мін, макс) сили «різні кроки світлоти»: |ΔL*| понад поріг, межа розмита σ (σ = 0 — тверда)."""
    лo = max(0.0, ра["L"][0] - рб["L"][1], рб["L"][0] - ра["L"][1])
    лh = max(ра["L"][1] - рб["L"][0], рб["L"][1] - ра["L"][0])
    if сигма <= 0.0:
        return (1.0 if лo >= поріг else 0.0, 1.0 if лh >= поріг else 0.0)
    s = сигма * math.sqrt(2.0)
    п = lambda Δ: _ф(Δ - поріг, s) + _ф(-Δ - поріг, s)
    return (п(лo), п(лh))


def _тепло(дуга):
    """(мін, макс) теплоти cos(k − `ТЕПЛИЙ_ПОЛЮС`) над дугою кола художника; None — будь-яка."""
    if дуга is None:
        return (-1.0, 1.0)
    ш = (дуга[1] - дуга[0]) % 360.0
    кк = [дуга[0] + ш * i / 12.0 for i in range(13)]
    вв = [math.cos(math.radians(k - ТЕПЛИЙ_ПОЛЮС)) for k in кк]
    if _КР._на_дузі(ТЕПЛИЙ_ПОЛЮС, дуга):
        вв.append(1.0)
    if _КР._на_дузі((ТЕПЛИЙ_ПОЛЮС + 180.0) % 360.0, дуга):
        вв.append(-1.0)
    return (min(вв), max(вв))


def сила(a, b, клас, певність=True, поріг=None):
    """(мін, макс) сили відношення `клас` (з `КЛАСИ`) між кольорами двох речей чи елементів, 0…1.

    Два виміри — одна сила двічі; вікно слова — межі сили по всіх його точках; кольору нема —
    `НЕВІДОМО`. Класи тону (`ВІКНА_ТОНУ`) — `у_вікні` відстані тонів на колі художника з розмиттям
    `СІГМА_МЕЖІ`, помножене на певність тону обох (`певність=False` — без множника: правило, що саме
    зважує, чи річ має тон, бере чисте відношення тону).
    `value_step` — |ΔL*| понад `поріг` (типово `step_min`, K-COL-01) з розмиттям `СІГМА_СВІТЛОТИ`;
    `tonal` — той самий тон і крок світлоти (K-COL-03 §2); `echo` — той самий тон без кроку, обидва
    гучні (K-COMP-05); `warm_cool` — контраст теплого й холодного Іттена: пів різниці теплоти
    cos(k − 30°), на певність; `achromatic` — 1 − τa·τb: пара тримається кольором без тону."""
    ра, рб = _КР.запис_кольору(a), _КР.запис_кольору(b)
    if ра is None or рб is None:
        return НЕВІДОМО
    τа, τб = (певність_тону(a), певність_тону(b)) if певність else ((1.0, 1.0), (1.0, 1.0))
    if клас in ВІКНА_ТОНУ:
        р = _КР._розкид_дуг(ра["коло"], рб["коло"])
        if клас in ВІКНА_ΔH:
            return _добуток(_ближній_тон(a, b, клас, р), τа, τб)
        return _добуток(_у_вікні_меж(р, ВІКНА_ТОНУ[клас], СІГМА_МЕЖІ), τа, τб)
    if клас == "value_step":
        return _крок_світлоти(ра, рб, C["step_min"] if поріг is None else поріг, СІГМА_СВІТЛОТИ)
    if клас == "tonal":
        return _добуток(сила(a, b, "same_hue", певність), сила(a, b, "value_step", поріг=поріг))
    if клас == "echo":
        к = сила(a, b, "value_step", поріг=поріг)
        return _добуток(сила(a, b, "same_hue", певність), (1.0 - к[1], 1.0 - к[0]), _гучна(a), _гучна(b))
    if клас == "warm_cool":
        та, тб = _тепло(ра["коло"]), _тепло(рб["коло"])
        р = (max(0.0, та[0] - тб[1], тб[0] - та[1]) / 2.0, max(та[1] - тб[0], тб[1] - та[0]) / 2.0)
        return _добуток(р, τа, τб)
    if клас == "achromatic":
        return (1.0 - τа[1] * τб[1], 1.0 - τа[0] * τб[0])
    raise ValueError("клас відношення %r поза КЛАСИ" % (клас,))


def сили(a, b, певність=True):
    """{клас: (мін, макс)} усіх `КЛАСИ` для пари кольорів."""
    return {к: сила(a, b, к, певність) for к in КЛАСИ}


def вердикт(с):
    """«так» / «ні» / «невідомо» сили-інтервалу зрізом 0.5 — межею вікна, яку поставили власник і
    корпус: «так» — уся сила від 0.5, «ні» — уся нижче, інакше «невідомо» (як `колір_річ.відношення`)."""
    return "так" if с[0] >= 0.5 else "ні" if с[1] < 0.5 else "невідомо"


def перевага(с):
    """(мін, макс) переваги 2·сила − 1, −1…1: на межі вікна 0, у ядрі 1, далеко поза вікном −1. Правило,
    що судить «відношення є / нема», бере знахідку з силою |перевага| — без стрибка на межі."""
    return (2.0 * с[0] - 1.0, 2.0 * с[1] - 1.0)
