"""Відсутній вхід правила: одна форма питання, нуль ваги, названі поля й речі."""
from functools import wraps

НЕМА_ВХОДУ = "питання"


def нема_входу(з):
    """Розпізнає брак входу, включно зі старими записами на межі ланцюга."""
    return isinstance(з, dict) and (з.get("сила") == НЕМА_ВХОДУ
        or з.get("регістр") == НЕМА_ВХОДУ or bool(з.get("без_входу")))


def уніфікувати(з):
    """Зводить історичні форми браку входу до питання без сили й заборони."""
    if нема_входу(з):
        з.update(сила=НЕМА_ВХОДУ, регістр=НЕМА_ВХОДУ, сила_нп=0.0, блокує=False)
        з.setdefault("сила_нп_джерело", "rule_input_missing")
        з.setdefault("без_входу", "вхід_правила")
        for к in ("для_стиліста", "впевненість", "під_підлогою"):
            з.pop(к, None)
    return з


def брак(правило, речі, поля, чому=None):
    """Повертає питання про конкретні відсутні поля без підставного числа."""
    from реєстр_правил import зн
    import внутрішня_мова as мова
    іди = [р.get("річ") or р.get("id") for р in речі]
    заяви = [мова.заява("rule_input_missing", fields=list(поля), items=іди)]
    return dict(зн(правило, НЕМА_ВХОДУ, мова.суть_кодом(заяви, іди), іди,
        чому or "rule_input_missing", заяви=заяви),
        без_входу="rule_input_missing", бракує=[dict(field=п, items=іди) for п in поля])


def бракує(речі, поля):
    """Знаходить речі з відсутнім входом; виміряний нуль лишається входом."""
    return [р for р in речі if any(р.get(п) is None for п in поля)]


def потребує(правило, *поля, коли=None):
    """Зупиняє суд списку елементів питанням, якщо його потрібних полів нема."""
    def огорнути(функція):
        """Зберігає ім'я й контракт функції суду."""
        @wraps(функція)
        def з_входом(E, *аргументи, **іменовані):
            """Перевіряє вхід до обчислення, а не після підстановки типового."""
            відсутні = бракує([р for р in E if коли is None or коли(р)], поля)
            if відсутні:
                return [брак(правило, відсутні, поля)]
            return функція(E, *аргументи, **іменовані)
        return з_входом
    return огорнути
