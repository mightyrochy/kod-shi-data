# ── ВИБІРКА ─────────────────────────────────────────────────────────────────
def вибірка(offers, на_слот=6, сід=17, крім=ЗАГЛУШКОВІ_КРАМНИЦІ):
    """По `на_слот` речей з кожної групи слота, сід 17, без «заглушкових» крамниць.

    Рівно по стільки з кожного слота, а не пропорційно каталогу: у пропорції
    прикрас було б 0.5 речі, а саме на них ATR і падає — прогін має це показати.
    """
    за_слотом = collections.defaultdict(list)
    for o in offers:
        if (o.get("магазин") or "") in крім:
            continue
        if not (o.get("фото") or o.get("фото_сирі")):
            continue
        try:
            с = F.слоти(o).get("слот")
        except Exception as _e:
            import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
            if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
            с = None
        if not с:
            continue
        за_слотом[група_слота(с)].append(o)
    вих = []
    for слот in sorted(за_слотом):
        речі = sorted(за_слотом[слот], key=lambda x: x["id"])
        random.Random(сід).shuffle(речі)
        вих.extend(речі[:на_слот])
    return вих


# ── ПОВНИЙ ПРОГІН ПО КАТАЛОГУ ───────────────────────────────────────────────
# Вибірка (60 речей) качала УСІ фото наперед, а потім міряла. На 12 405 речах це
# 75 тис. файлів ≈ 6 ГБ на диску і година простою GPU перед першим виміром. Тому
# повний прогін — конвеєр: качалки йдуть на N речей уперед (стеля черги = стеля
# диска), міряльники беруть готове, а кеш фото речі гине відразу після її запису.
def _не_спати(вимкнути=False):
    """Windows: не давати ноутбуку заснути, поки прогін іде (жниварка._не_спати)."""
    try:
        import ctypes
        ctypes.windll.kernel32.SetThreadExecutionState(0x80000000 if вимкнути else 0x80000001)
        return True
    except Exception as _e:
        import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
        if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
        return False


def _url_крамниць(offers):
    """({магазин: {адреса: у скількох речах}}, {магазин: стеля повторів}).

    Той самий файл у крамниці видно з КАТАЛОГУ, без жодного скачування: потоковий
    прогін так дізнається про логотип уже на ПЕРШІЙ речі крамниці, тоді як
    лічильник хешів набирається лише по ходу. Стеля — п'ята частина крамниці, але
    не менше дев'яти: логотип стоїть майже в кожній речі (sezone.ua — ті самі 12
    фото в усіх 256), а варіант однієї речі повторюється в одиницях.
    """
    лічильник, речей = collections.defaultdict(collections.Counter), collections.Counter()
    for o in offers:
        м = o.get("магазин") or ""
        речей[м] += 1
        for u in {збільшити_url(x) for x in (o.get("фото") or o.get("фото_сирі") or [])}:
            лічильник[м][u] += 1
    return лічильник, {м: max(9, n // 5) for м, n in речей.items()}


def повний(offers, а):
    """Усі офери каталогу → {id: запис} у `--вихід`, з продовженням після обриву."""
    вільно = shutil.disk_usage(tempfile.gettempdir()).free / 2 ** 30
    if вільно < 5:
        raise SystemExit("на диску %.1f ГБ — мало для кешу фото, треба ≥ 5" % вільно)
    лог = open(а.лог, "a", encoding="utf-8") if а.лог else None

    def каж(текст):
        """Рядок у лог (або на екран) з часом."""
        рядок = "%s  %s" % (time.strftime("%H:%M:%S"), текст)
        print(рядок, file=лог or sys.stdout, flush=True)

    готове = {}
    if а.продовжити and os.path.exists(а.вихід):
        with open(а.вихід, encoding="utf-8") as f:
            усе = json.load(f)
        готове = {к: з for к, з in усе.items() if "помилка" not in з}
        каж("продовження: у файлі %d записів, придатних %d — решту перероблю"
            % (len(усе), len(готове)))
    черга = [o for o in offers if o["id"] not in готове]
    if а.ліміт:
        черга = черга[:а.ліміт]
    каж("повний прогін: каталог %d, лишилось %d, потоків %d, качалок %d, вільно %.0f ГБ"
        % (len(offers), len(черга), а.потоки, а.качалок, вільно))
    _не_спати()

    url_лічильник, стелі = _url_крамниць(offers)
    хеші = collections.defaultdict(collections.Counter)
    зам = threading.Lock()
    вхід, фото_q, вихід_q = queue.Queue(), queue.Queue(maxsize=а.потоки * 3), queue.Queue()
    for o in черга:
        вхід.put(o)

    def качальник():
        """Потік-качалка: офер із черги → фото в кеш → відсів заглушок (з підстраховкою
        сторінкою товару) → черга міряльників; повна черга — це і є стеля диска."""
        while True:
            try:
                o = вхід.get_nowait()
            except queue.Empty:
                return
            try:
                фото = взяти_фото(o, а.фото, мітка=o["id"])
            except Exception as e:
                фото = [dict(помилка=str(e)[:150])]
            м = o.get("магазин") or ""

            def відсіяти(фото):
                """Заглушки цієї речі під замком: повтори за хешем і за адресою з каталогу."""
                with зам:
                    for ф in фото:
                        if ф.get("хеш"):
                            хеші[м][ф["хеш"]] += 1
                    позначити_одну(фото, lambda ф: max(хеші[м][ф["хеш"]] if ф.get("хеш") else 0,
                                                       url_лічильник[м][збільшити_url(ф["url"])]),
                                   стеля=стелі.get(м, 9))
            відсіяти(фото)
            # Фід і правило розміру дали самі заглушки → третій крок, сторінка товару.
            if o.get("url") and not any(ф.get("шлях") and not ф.get("заглушка") for ф in фото):
                зі_сторінки = фото_зі_сторінки(o, а.фото, мітка=o["id"])
                відсіяти(зі_сторінки)
                фото = фото + зі_сторінки
            фото_q.put((o, фото))          # черга повна → качалка чекає: це і є стеля диска

    def міряльник():
        """Потік-міряльник: `обробити` на готових фото, кеш речі геть, запис у вихідну чергу;
        збій — запис із `помилка`, щоб `--продовжити` перепробував."""
        while True:
            п = фото_q.get()
            if п is None:
                return
            o, фото = п
            try:
                з = обробити(o, фото, а.модель, показ=False)
            except Exception as e:
                з = dict(id=o["id"], магазин=o.get("магазин"),
                         помилка=("%s: %s" % (type(e).__name__, e))[:200])
            прибрати_кеш(фото)
            вихід_q.put(з)

    качалки = [threading.Thread(target=качальник, daemon=True) for _ in range(а.качалок)]
    міряльники = [threading.Thread(target=міряльник, daemon=True) for _ in range(а.потоки)]
    for т in качалки + міряльники:
        т.start()

    def сторож():
        """Дочекатись качалок і покласти міряльникам стоп-сигнали."""
        for т in качалки:
            т.join()
        for _ in міряльники:
            фото_q.put(None)
    threading.Thread(target=сторож, daemon=True).start()

    t0, збоїв, маски = time.time(), 0, collections.Counter()
    останні = collections.deque(maxlen=200)
    n, сотня, тиша = 0, time.time(), time.time()
    while n < len(черга):
        try:
            з = вихід_q.get(timeout=60)
        except queue.Empty:
            # Мовчання довше за хвилину — це або мертвий хост фото, або завислий
            # сервер. Уночі його нікому помітити, тому воно йде в лог саме.
            каж("тиша %.0f с на %d/%d: у черзі фото %d" % (time.time() - тиша, n,
                                                           len(черга), фото_q.qsize()))
            тиша = time.time()
            continue
        тиша = time.time()
        n += 1
        готове[з["id"]] = з
        збоїв += "помилка" in з
        останні.append("помилка" in з)
        маски[(з.get("маска") or {}).get("джерело") or "—"] += 1
        if n % 50 == 0 or n == len(черга):
            записати_атомарно(готове, а.вихід)
        # СТОРОЖ НОЧІ: коли падає майже все підряд — це не каталог, а впалий сервер
        # (LM Studio чи ComfyUI). Далі йти немає сенсу: `--продовжити` перепробує.
        if len(останні) == 200 and sum(останні) >= 190:
            записати_атомарно(готове, а.вихід)
            каж("СТОП на %d: 190+ збоїв з останніх 200 — перевір LM Studio і ComfyUI" % n)
            break
        if n % 100 == 0 or n == len(черга):
            темп, сотня_с = (time.time() - t0) / n, (time.time() - сотня) / min(n, 100)
            сотня = time.time()
            # Два темпи, бо вони розходяться: середній ховає просідання, темп
            # останньої сотні показує його того ж вечора. Залишок — по останній.
            каж("%d/%d  збоїв %d (%.1f %%)  %.2f с/річ (середнє %.2f)  лишилось %.1f год  маски %s"
                % (n, len(черга), збоїв, 100.0 * збоїв / n, сотня_с, темп,
                   сотня_с * (len(черга) - n) / 3600.0, dict(маски)))
    _не_спати(вимкнути=True)
    каж("готово: %d записів у файлі, пройдено %d, збоїв %d, %.2f год"
        % (len(готове), n, збоїв, (time.time() - t0) / 3600.0))
    каж("файл: %s" % а.вихід)
    if лог:
        лог.close()
    return готове


# ── ПРОБА РЕФЕРЕРА ──────────────────────────────────────────────────────────
def проба_реферера(offers, на_крамницю=3):
    """Чи дають п'ять «заглушкових» крамниць справжнє фото, коли є Referer.

    V1 дістала з них 1 240 логотипів. Якщо це хотлінк-захист, з Referer байти
    будуть інші — і тоді 1 362 речі повертаються в каталог, а не списуються.
    """
    за_крамницею = collections.defaultdict(list)
    for o in offers:
        м = o.get("магазин") or ""
        if м in ЗАГЛУШКОВІ_КРАМНИЦІ and (o.get("фото") or o.get("фото_сирі")):
            за_крамницею[м].append(o)
    вих = {}
    for м, речі in sorted(за_крамницею.items()):
        random.Random(17).shuffle(речі)
        рядки = []
        for o in речі[:на_крамницю]:
            url = (o.get("фото") or o.get("фото_сирі"))[0]
            р = dict(id=o["id"], url=url)
            for мітка, реф in (("без", None), ("з", "https://%s/" % м)):
                try:
                    b = _качати(url, реферер=реф)
                    р[мітка] = dict(байтів=len(b), хеш=hashlib.md5(b).hexdigest()[:12],
                                    майже_біле=_майже_біле(_відкрити(b)))
                except Exception as e:
                    р[мітка] = dict(помилка=str(e)[:100])
            р["інші_байти"] = (р["без"].get("хеш") != р["з"].get("хеш"))
            рядки.append(р)
        вих[м] = рядки
        print("%-20s %s" % (м, json.dumps(рядки, ensure_ascii=False)[:300]), flush=True)
    return вих


# ── ГОЛОВНЕ ─────────────────────────────────────────────────────────────────
def main():
    """Аргументи командного рядка → один із прогонів: --вибірка, --повний, --злити, --реферер."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--вибірка", action="store_true", help="прогнати вибірку 60 речей")
    ap.add_argument("--повний", action="store_true", help="усі офери каталогу → каталог_збагачення_v2.json")
    ap.add_argument("--продовжити", action="store_true", help="повний: пропустити готове, збої перепробувати")
    ap.add_argument("--злити", action="store_true", help="v2 поверх v1 → каталог_збагачення.json.gz")
    ap.add_argument("--злити-у", default=None, help="інша ціль злиття (для сухого прогону)")
    ap.add_argument("--лог", default=None, help="повний: файл лога (без нього — на екран)")
    ap.add_argument("--качалок", type=int, default=6, help="повний: потоків, що качають фото наперед")
    ap.add_argument("--реферер", action="store_true", help="проба Referer на п'яти крамницях")
    ap.add_argument("--на-слот", type=int, default=6)
    ap.add_argument("--ліміт", type=int, default=None, help="узяти лише перші N речей вибірки")
    ap.add_argument("--потоки", type=int, default=3)
    ap.add_argument("--фото", type=int, default=6, help="скільки фото речі качати")
    ap.add_argument("--модель", default="qwen3-vl-8b-instruct")
    ap.add_argument("--каталог", default=КАТАЛОГ)
    ap.add_argument("--вихід", default=None)
    а = ap.parse_args()
    if а.вихід is None:
        а.вихід = ПОВНИЙ_ФАЙЛ if (а.повний or а.злити) else ВИБІРКА_ФАЙЛ
    if а.злити:                      # каталог тут ні до чого — зливаються два готові файли
        злити(а)
        return

    import gzip
    відкр = gzip.open if а.каталог.endswith(".gz") else open
    with відкр(а.каталог, "rb") as f:
        offers, _ = F.читати_yml(f)
    print("каталог: %d речей" % len(offers), flush=True)

    if а.повний:
        повний(offers, а)
        return

    if а.реферер:
        дані = проба_реферера(offers)
        print(json.dumps({k: len([r for r in v if r.get("інші_байти")]) for k, v in дані.items()},
                         ensure_ascii=False))
        return

    if not а.вибірка:
        ap.error("вкажи --вибірка, --повний, --злити або --реферер")

    речі = вибірка(offers, на_слот=а.на_слот)
    if а.ліміт:
        речі = речі[:а.ліміт]
    print("вибірка: %d речей, слотів %d" % (
        len(речі), len({група_слота(F.слоти(o).get('слот')) for o in речі})), flush=True)

    t0 = time.time()
    фото_речей, магазини = {}, {}
    with ThreadPoolExecutor(8) as пул:
        майб = {пул.submit(взяти_фото, o, а.фото): o for o in речі}
        for м in as_completed(майб):
            o = майб[м]
            магазини[o["id"]] = o.get("магазин")
            try:
                фото_речей[o["id"]] = м.result()
            except Exception as e:
                фото_речей[o["id"]] = [dict(помилка=str(e)[:120])]
    позначити_заглушки(фото_речей, магазини)
    качано = sum(len(v) for v in фото_речей.values())
    заглушок = sum(1 for v in фото_речей.values() for ф in v if ф.get("заглушка"))
    print("фото: %d скачано, %d заглушок, %.0f с" % (качано, заглушок, time.time() - t0), flush=True)

    записи, збоїв = [], 0
    замок = threading.Lock()
    with ThreadPoolExecutor(а.потоки) as пул:
        майб = {пул.submit(обробити, o, фото_речей[o["id"]], а.модель): o for o in речі}
        for м in as_completed(майб):
            o = майб[м]
            try:
                з = м.result()
            except Exception as e:
                з = dict(id=o["id"], магазин=o.get("магазин"), помилка=str(e)[:200])
            with замок:
                записи.append(з)
                збоїв += "помилка" in з
                if len(записи) % 10 == 0 or len(записи) == len(речі):
                    print("%s  %d/%d  збоїв %d  %.0f с" % (time.strftime("%H:%M:%S"), len(записи),
                                                           len(речі), збоїв, time.time() - t0), flush=True)

    записи.sort(key=lambda з: (з.get("слот") or "", з["id"]))
    os.makedirs(os.path.dirname(а.вихід), exist_ok=True)
