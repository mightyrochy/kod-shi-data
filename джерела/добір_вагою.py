"""Сіяний добір без повернення зі спільною вагою для речей одного рівня."""

from heapq import nsmallest
from math import log1p
from random import Random

РЕЄСТР = {
    "вага_на_крок": {"val": 0.5, "t": 3, "прав": [], "джерело": "аудит/ПРОДУКТ.md, п. 9"},
    "рівні": {"val": 3, "t": 3, "прав": [], "джерело": "семплер: яруси пізніх ключів"},
}


def рівні(ранги):
    """Повертає рівень кожної речі за кількістю ключів, гірших за мінімум."""
    вимірів = max(map(len, ранги), default=0)
    краще = [min(ранг[і] for ранг in ранги if і < len(ранг)) for і in range(вимірів)]
    стеля = РЕЄСТР["рівні"]["val"] - 1
    return [min(стеля, sum(x > краще[і] for і, x in enumerate(ранг))) for ранг in ранги]


def добрати(ранги, квота, сід):
    """Добирає ідентифікатори слота в порядку зваженої випадкової черги.

    Експоненційні ключі дають кожній ще доступній речі шанс на наступне місце
    пропорційно її вазі 1, ½ або ¼. Префікси однієї черги сумісні між квотами.
    """
    if квота <= 0 or not ранги:
        return []
    іди = sorted(ранги)
    яруси = рівні([ранги[ід] for ід in іди])
    if not сід:
        return sorted(іди, key=dict(zip(іди, яруси)).__getitem__)[:квота]
    випадок = Random(f"{сід}|добір")
    if len(set(яруси)) == 1:
        випадок.shuffle(іди)
        return іди[:квота]
    вага = РЕЄСТР["вага_на_крок"]["val"]
    ключі = {ід: -log1p(-випадок.random()) / вага ** л for ід, л in zip(іди, яруси)}
    return nsmallest(квота, іди, key=ключі.__getitem__)
