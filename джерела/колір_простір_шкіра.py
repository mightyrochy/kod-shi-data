# D4, УТОЧНЕНО ДОСЛІДЖЕННЯМ (Kang 2025, Benčević 2025, огляди ITA): для КЛАСИФІКАЦІЇ
# шкіри критична вісь — b*, не L*. Похідна ITA по b* велика для типових тонів шкіри,
# тож ITA набагато чутливіша до шуму в СИНЬОМУ каналі, ніж підказує загальна ΔE; навіть
# підпороговий шум b* дає градусні коливання ITA й ламає підтип. Смартфон проти
# спектрофотометра: ΔE00≈7.6 (Niakan 2025, n=50); корекція за колірною картою знімає
# ~65-70% міжприладової й світлової варіації. Практичний наслідок: σ тримати ОКРЕМО по
# осях, найтугіший контроль на b*; головна дія — референсна колірна карта в протоколі
# зйомки, а не підбір скалярного σ. (Числа профілю в profile.Σ поки скалярні по L*.)
def hair_photo_uncertainty(protocol="uncontrolled"):
    """ВОЛОССЯ з фото фіксованим зсувом НЕ коригується — так само, як шкіра.

    Раніше тут стояла корекція −33.4 L* (Grimes 2009, n=134). Перше ж реальне фото
    показало, що вона ламає профіль: блондинка з виміряними L*68 ставала L*35, тобто
    брюнеткою, і контраст особи рахувався не на тій людині.

    Я спробував врятувати константу згасанням за світлотою — не вийшло: жодне
    застосування не проходить перевірки на осудність по всьому природному діапазону.
      · сталий зсув:            L*68 -> 35 (блондинка стає брюнеткою)
      · згасання за світлотою:  L*25 -> 2  (темно-каштанове стає чорнішим за чорне)
      · шринкедж за r=.63:      L*68 -> 33 (те саме, з іншого боку)
    Причина в самому джерелі: r=.63/.59/.51 означає, що зв'язок фото↔спектрофотометр
    не є одиничним нахилом. Середня різниця по вибірці справедлива БІЛЯ СЕРЕДНЬОГО
    і не переноситься на окремий зразок. Фізично зсув дає глянець і вуаль, а їхній
    внесок різко залежить від світлоти й геометрії світла — це не адитивна стала.

    Тому константа лишається в реєстрі з джерелом, але НЕ застосовується. Замість
    корекції — оголошена невизначеність, як зроблено для шкіри."""
    return {"protocolized": dict(l_sigma=4.0,
                note="геометрія й світло контрольовані: залишковий вплив глянцю малий"),
            "uncontrolled": dict(l_sigma=12.0,
                note="дзеркальне селфі / змішане світло: L* волосся може гуляти на десяток "
                     "одиниць; висновки будувати на відносних порівняннях, не на абсолюті")
           }[protocol]

# `from_image` → лабораторія/без_викликача.py (Н-02-02: ДОСЯЖНІСТЬ 13.09 — «ніхто»)

def skin_photo_uncertainty(protocol="uncontrolled"):
    """ШКІРУ фіксованим зсувом не коригуємо: підповерхневе розсіювання + бліки.
    Замість корекції — невизначеність, залежна від протоколу зйомки (Burrow'24/Kang'25)."""
    return {"protocolized": dict(ita_sigma=1.0, note="геометрія/світло/експозиція контрольовані"),
            "uncontrolled": dict(ita_sigma=8.0, note="некалібровано: ITA ненадійна, b*-шум домінує")
           }[protocol]

# ─────────────────────────── ШКІРА ────────────────────────────────────────
def ita(L,b): return math.degrees(math.atan2(L-50,b)) if b else float("nan")
def ita_band(i):
    """Єдиний шлях смуги ITA. nan (b*≈0) -> явна невизначеність, не краш."""
    if i!=i: return "невизначена (b*≈0)"
    return next(n for lo,hi,n in ITA_BANDS if lo<=i<hi)
ITA_BANDS=[(55,1e9,"very light"),(41,55,"light"),(28,41,"intermediate"),
           (10,28,"tan"),(-30,10,"brown"),(-1e9,-30,"dark")]
ITA_DOMAIN = REGISTRY["ita_domain"]["val"]   # область значень atan2(L*-50, b*) при b*>0

def _норм_cdf(x): return 0.5*(1.0+math.erf(x/math.sqrt(2.0)))

def _σ_lab_з_σ_ita(lab, σ_ita):
    """ЯКОБІАН ita(): переводить σ по ITA° в σ по (L*, b*).
    ITA = atan2(L*−50, b*); при r = |(L*−50, b*)| похідна кута по будь-якому
    напрямку в площині (L*, b*) дорівнює 1/r рад на одиницю Lab, тож
    σ_Lab = σ_ITA[рад]·r. Без цього переходу число з протоколу зйомки
    (градуси) клалося просто на координати Lab (одиниці Lab) — різні одиниці."""
    r = math.hypot(lab[0]-50.0, lab[2])
    return math.radians(σ_ita)*r if σ_ita>0 and r>0 else 0.0

def ita_band_mass(μ, σ):
    """Маса нормального розподілу ITA° у кожному кошику ITA_BANDS.
    σ — у ГРАДУСАХ ITA. Кошики обрізано областю ITA_DOMAIN: крайні писані як
    ±1e9, а маса на нескінченному кошику не визначена; після обрізання розподіл
    нормується на область, тож сума мас дорівнює 1 і смуга не залежить від сіду."""
    if μ != μ: return {ita_band(float("nan")): 1.0}
    if σ <= 0:  return {ita_band(μ): 1.0}
    низ, верх = ITA_DOMAIN
    Z = _норм_cdf((верх-μ)/σ) - _норм_cdf((низ-μ)/σ)
    if Z <= 0: return {ita_band(μ): 1.0}
    маси = {}
    for lo,hi,name in ITA_BANDS:
        a, b = max(lo, низ), min(hi, верх)
        if b <= a: continue
        маси[name] = (_норм_cdf((b-μ)/σ) - _норм_cdf((a-μ)/σ)) / Z
    return маси

def skin_pos(lab, sigma=0.0, protocol=None):
    """`sigma` — невизначеність у ГРАДУСАХ ITA (як її й подає протокол зйомки:
    skin_photo_uncertainty повертає `ita_sigma`), а НЕ шум по координатах Lab.
    Раніше це число сипалось гаусом просто на (L*,a*,b*): на #deb295 радіус
    (L*−50, b*) = 33.2, тож обіцяні 8° давали ≈15° по ITA. Тепер σ переходить у
    Lab через якобіан ita() — і лише по (L*, b*), бо ITA від a* не залежить, а
    a* лицьової шкіри інваріантне по популяціях (див. REGISTRY['olive']).
    ITA і band_p рахуються аналітично з (μ, σ), тому не тремтять від сіду;
    кидки лишаються тільки там, де форма локусу нелінійна — p_in_locus/p_olive."""
    if protocol: sigma = max(sigma, skin_photo_uncertainty(protocol)["ita_sigma"])
    μ_ita = ita(lab[0], lab[2])
    σ_lab = _σ_lab_з_σ_ita(lab, sigma)
    n = 200 if σ_lab>0 else 1; loc=0.; olv=0.
    for _ in range(n):
        if σ_lab>0:
            L,a,b = lab[0]+random.gauss(0,σ_lab), lab[1], lab[2]+random.gauss(0,σ_lab)
        else:
            L,a,b = lab
        _,C,h = lch((L,a,b))
        loc += soft(h,*CONST["skin_h"][0],WIDTHS["h"])*soft(C,*CONST["skin_C"][0],WIDTHS["C"])/n
        olv += soft(h,CONST["olive"][0][0],120,WIDTHS["b"])*(1-soft(a,-50,CONST["olive"][0][1],2.))/n
    bands = ita_band_mass(μ_ita, sigma)
    return dict(ITA=round(μ_ita, 1) if μ_ita == μ_ita else float('nan'),
        ITA_σ=round(sigma, 1) if μ_ita == μ_ita else 0.0,   # неперервна невизначеність, ГРАДУСИ ITA
        band_p={k:round(v,2) for k,v in sorted(bands.items(),key=lambda x:-x[1]) if round(v,2)>0},
        p_in_locus=round(loc,2), p_olive=round(olv,2),
        photo_note=(skin_photo_uncertainty(protocol)["note"] if protocol else None),
        tier=tier("skin_h","olive"))

