# Словники ВИНЕСЕНО у lexicons/*.json (дані, не код). Геометрія від них не залежить.
def L_from_ht(ht):
    lo,hi=CONST["ht_anchors"][0]
    return lo+(hi-lo)*((max(1,min(10,ht))-1)/9)**(1/CONST["ht_power"][0][0])
def ht_from_L(L):
    lo,hi=CONST["ht_anchors"][0]
    return round(1+9*max(0.,min(1.,(L-lo)/(hi-lo)))**CONST["ht_power"][0][0],1)
ACHROMATIC_C = 2.0        # T3: нижче цього C* тон — шум округлення, не колір

# ── ЯКІР ПІДТОНУ: тепер із реєстру, а не голим літералом усередині функції ──
ЦЕНТР_ПІДТОНУ, РОЗКИД_ПІДТОНУ = REGISTRY["undertone_anchor"]["val"]
# межі касту ББ — одне число на colorspace й extract (двійник зведено)
КАСТ_ББ = (4.0, 10.0)   # дзеркало реєстр_правил.REGISTRY["каст_ББ"]; той модуль
                        # імпортує colorspace, тож зворотне читання дало б цикл
# Оголошена популяція: проєкт цілиться в український ринок, тобто в європейський
# T1-діапазон тону шкіри. Знак осі перевіряється САМЕ проти нього — вісь, чий знак
# не населений на популяції, яку вона побачить, не міряє знак, а призначає його.
ПОПУЛЯЦІЯ_ПІДТОНУ = "skin_h_eu"
МЕЖА_КЛАСУ_ПІДТОНУ = 0.5   # |тепло_сила|, за якої клас перестає бути «нейтральним»


def вісь_підтону_двостороння(популяція=None, N=400):
    """Чи має вісь підтону обидві сторони НА ЦІЙ ПОПУЛЯЦІЇ.

    КОЛИ ДІЄ: завжди, коли хтось збирається сказати ЗНАК підтону («тепла»/«холодна»).
    НАСКІЛЬКИ: жорстко — порожня сторона робить знак не-виміром.
    ДЕ ЛАМАЄТЬСЯ: діапазон популяції сам T1-опублікований, тобто це межі вибірки,
    а не щільність. Реальний розподіл усередині може бути ще вужчим; перевірка
    оптимістична, і якщо навіть вона каже «порожньо» — питання закрите."""
    lo, hi = REGISTRY[популяція or ПОПУЛЯЦІЯ_ПІДТОНУ]["val"]
    ч = {"холодна": 0, "нейтральна": 0, "тепла": 0}
    for i in range(N + 1):
        s = ((lo + (hi - lo) * i / N) - ЦЕНТР_ПІДТОНУ) / РОЗКИД_ПІДТОНУ
        ч["тепла" if s > МЕЖА_КЛАСУ_ПІДТОНУ else
          "холодна" if s < -МЕЖА_КЛАСУ_ПІДТОНУ else "нейтральна"] += 1
    частки = {k: round(100 * v / (N + 1), 1) for k, v in ч.items()}
    порожні = [k for k, v in частки.items() if v == 0.0 and k != "нейтральна"]
    return dict(двостороння=not порожні, частки=частки, порожні=порожні,
                діапазон=(lo, hi), популяція=популяція or ПОПУЛЯЦІЯ_ПІДТОНУ,
                межі_класів=(round(ЦЕНТР_ПІДТОНУ - МЕЖА_КЛАСУ_ПІДТОНУ * РОЗКИД_ПІДТОНУ, 1),
                             round(ЦЕНТР_ПІДТОНУ + МЕЖА_КЛАСУ_ПІДТОНУ * РОЗКИД_ПІДТОНУ, 1)))
HAIR_NEUTRAL_AB = (6.0, 9.0)   # T3-якір: нейтраль ВОЛОССЯ коричнева, не сіра (Lee 2024)
def achromatic(lab):
    """Чи є тон ВЗАГАЛІ — питання абсолютне (відстань від СІРОГО), однакове для всього.
    Коричнева нейтраль волосся (Lee 2024) стосується ІНШОГО питання — теплий/попелястий
    відносно типового волосся — і живе у hair_cast(), а не тут.
    (Раніше я плутав ці два питання, і каштанове волосся ставало «безбарвним».)
    Параметр `kind` прибрано: він лишався в сигнатурі ПІСЛЯ того, як питання стало
    однаковим для всіх рис — тобто обіцяв розрізнення, якого тіло вже не робило."""
    L,C,h = lch(lab)
    return C < ACHROMATIC_C, C

def hair_cast(lab):
    # K-TIME-01 (24.08.2026): ахроматичне (сиве/біле) волосся температури НЕ несе —
    # якір нейтралі коричневий (Lee 2024) стосується лише пігментованого волосся.
    if lch(lab)[1] < ACHROMATIC_C:
        return {"відхилення": 0.0, "каст": "сиве/ахроматичне: температури не несе"}
    """Наскільки волосся тепліше/попелястіше за ТИПОВЕ волосся (Lee 2024: нуль-точка
    коричнева, не сіра). Це опис, а не підстава прибирати тоновий голос."""
    da, db = lab[1]-HAIR_NEUTRAL_AB[0], lab[2]-HAIR_NEUTRAL_AB[1]
    d = math.hypot(da, db)
    if d < 4: caste="типове коричневе"
    elif db < -3: caste="попелясте (холодніше за типове)"
    elif da > 6: caste="рудувате/тепліше за типове"
    elif db > 6: caste="золотисте/жовтіше за типове"
    else: caste="близьке до типового"
    return dict(відхилення=round(d,1), каст=caste)
# R-MUN-01 — дубль `colorspace.describe`: hue/value/chroma людським шаром над Lab.
def describe(lab, kind=None, lex=None):
    """Чисті координати. Тон None, якщо колір ахроматичний."""
    L,C,h=lch(lab); cm=c_max(L,h); rel=C/cm if cm>1e-6 else 0
    is_ach, d_neutral = achromatic(lab); hue_defined = not is_ach
    # hex СТАВИТЬСЯ ТУТ, БО ЧИТАЄТЬСЯ СКРІЗЬ (P29). До 11.09.2026 `hex` мав лише
    # макіяж — єдина риса, якій його клали руками з входу. `personal_palette`
    # читав `f.get("hex")` у п'яти місцях («її чорний», «її білий», нейтралі,
    # родини, макіяж) і на ДАНИХ рисах отримував None: читання виглядали живими,
    # а віддавали порожнечу. Риса завжди має lab — отже завжди може мати hex.
    d=dict(L=round(L,1), C=round(C,1), h=(round(h,1) if hue_defined else None),
           rel_C=round(rel,2), тон_визначений=hue_defined,
           відстань_до_нейтралі=round(d_neutral,1), hex=hex_з_lab(lab))
    if lex: d["назва"]=lex.describe(L,rel,h) if hue_defined else "нейтральний (без тону)"
    if kind=="волосся":
        d["HT"]=ht_from_L(L); d.update(hair_cast(lab))
    if kind=="шкіра":
        it=ita(L,lab[2])
        d["ITA"]=None if it!=it else round(it,1)
        d["ITA_смуга"]=ita_band(it)
    return d
