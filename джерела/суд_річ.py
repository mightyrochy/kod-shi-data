def тканина_проти_крою(E, розрив_макс=2.0):
    """K-MAT-01. Річ, у якій тканина й крій тягнуть у різні боки формальності."""
    зн = []
    for e in одна_на_річ(E):
        т = str(e.get("текстура") or "").strip().lower()
        тк = ТКАНИНА_ФОРМАЛЬНІСТЬ.get(т)
        # ВИПРАВЛЕНО ПІСЛЯ ПРОБИ: спершу тут стояв `інтервал_формальності(e)`, і
        # правило МОВЧАЛО на атласних спортивних штанях — бо полярність тканини вже
        # зсунула той інтервал угору (спортивний 1–3 + satin +1 + «атласн» +1 = 1–5),
        # тобто суперечність УЖЕ була усереднена в те саме число, з яким її порівнюють.
        # Правило міряло б власну поправку. Порівнювати треба з БАЗОВИМ інтервалом
        # ТИПУ — тим, що каже крій сам по собі, без тканини.
        кр_lo, кр_hi, _ = інтервал_типу(e.get("тип"))
        if not тк or кр_lo is None: continue
        # розрив = зазор між інтервалами, що дивляться один на одного
        розрив = max(0.0, тк[0] - кр_hi, кр_lo - тк[1])
        if розрив <= розрив_макс: continue
        сила_нп = round(min(1.0, (розрив - розрив_макс) / 3.0), 2)
        # ── ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026) ────────────────
        # before: «у „худі атласне“ тканина й крій тягнуть у різні боки» — той самий
        # рядок і на атласному худі (тканина формальніша за крій), і на джинсовому
        # костюмі (крій формальніший за тканину). «У різні боки» — це і є пропуск
        # боку: обидві заміни звучать однаково, а вони протилежні. Який кінець
        # тягнути, знав `ремонт` («та сама річ у тканині рівня …»), і саме він до
        # промпту ші не доїжджає.
        # after (два справжні рядки з двох прогонів):
        #   · у «худі атласне» тканина «satin» формальніша за крій «худі» — узяти
        #     тканину простішу [0.33]
        #   · у «костюм джинсовий» тканина «denim» простіша за крій «костюм» —
        #     узяти тканину формальнішу [0.33]
        # Бік — той самий доданок, з якого рядком вище вже порахований `розрив`:
        # `тк[0] - кр_hi > 0` означає тканину над кроєм. Рівнів у реченні нема,
        # вони лишились у `чому` й `ремонт`.
        _тканина_вище = тк[0] - кр_hi > 0
        зн.append(dict(_зн(
            "K-MAT-01", "soft" if сила_нп >= C["нп_межа_soft"] else "hint",
            "у «%s» тканина «%s» %s за крій «%s» — узяти тканину %s"
            % (e.get("річ") or e.get("id"), т,
               "формальніша" if _тканина_вище else "простіша",
               e.get("тип") or "?",
               "простішу" if _тканина_вище else "формальнішу"),
            [e.get("річ") or e.get("id")],
            "тканина «%s» читається як %d–%d, КРІЙ САМ ПО СОБІ «%s» як %.0f–%.0f — зазор %.1f при "
            "межі %.1f. Це розлад УСЕРЕДИНІ речі, тож розкид між речами образу може "
            "бути нульовим і K-KOH-02 мовчатиме"
            % (т, тк[0], тк[1], e.get("тип") or "?", кр_lo, кр_hi, розрив, розрив_макс),
            ремонт=["та сама річ у тканині рівня %d–%.0f" % (int(кр_lo), кр_hi),
                    "або той самий крій у рівні %d–%d" % (тк[0], тк[1])],
            запит=dict(слот=e.get("слот"), замість=e.get("річ"),
                       текстура_рівня=(int(кр_lo), int(кр_hi)),
                       чому="K-MAT-01: тканина проти крою"),
            ламається="шкала тканин — конвенція (T3), не вимір, і вона груба: одне "
                      "слово `текстура` не розрізняє важкий креп від легкого. Плюс "
                      "розлад буває НАВМИСНИЙ (атласні спортивні штани — цілий "
                      "редакційний жанр), тому це репліка, не гейт",
            поріг=розрив_макс, вимір=розрив, повна=3.0),
            сила_нп=сила_нп,
            сила_нп_джерело="вимір (власний: зазор між інтервалами тканини й крою)"))
    return зн
def _придатність_принтів(F, речі, E, source, масштаб_особи=None, зона_камуфляж=None,
                         надійність_масштабу=None):
    """Мостик до palette.принт_придатність (правила практиків про придатність
    принту ОСОБІ). Імпорт лінивий: palette імпортує outfit на рівні модуля, тож
    зворотний імпорт на рівні модуля дав би цикл; у момент виклику обидва вже є.

    Річ несе палітру принту в полі `принт` (його кладе feed.прогін для SKU з
    низькою впевненістю домінанти). Нема поля — правило не вигадує вхід і молчить."""
    видимі = {e["річ"] for e in E}
    зн = []
    # П.14 (20.09.2026): застава навколо імпорту знята. `palette` — модуль ядра
    # (`status.МОДУЛІ_ПРОДУКТУ`), імпорт лінивий лише проти циклу, не проти
    # відсутності. `ImportError` тут означав зламану збірку, а віддавав порожній
    # список знахідок — тобто «принти придатні» замість «шар не піднявся». Тепер
    # летить у `bridge.виклик` (`помилка` + `код`) і показ показує рядок жінці.
    import palette as _P
    for r in речі:
        пал = r.get("принт")
        if not пал or r["id"] not in видимі:
            continue
        # СЛОТ У ПАРАМЕТР СЛОТА, ІД І НАЗВА — ОКРЕМО (Н-palette-2-102). Досі сюди
        # їхав r["id"], і P-PRT-03 звіряв SKU з назвою слота: рівність не
        # виконувалась ніколи, правило зникало без сліду.
        рез = _P.принт_придатність(пал, F=F, source=source, масштаб_особи=масштаб_особи,
                                   зона_камуфляж=зона_камуфляж, слот_принту=r.get("слот"),
                                   надійність_масштабу=надійність_масштабу,
                                   річ_ім=r.get("назва") or r["id"], річ_ід=r["id"])
        зн += рез["знахідки"]
    return зн
