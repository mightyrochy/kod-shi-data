# ── K-PC-08: ВЕТО ПОКРИТТЯ — жорстке, структуроване, без переконування ─────
# Корпус: «Преференції "не відкриваю руки / декольте / ноги вище N / спину" — жорсткі
# обмеження БЕЗ ПОТРЕБИ ОБҐРУНТУВАННЯ, культурно й особисто зумовлені. Система не
# "переконує спробувати"». [принцип · hard]
#
# ЧОМУ ЦЕ ОКРЕМЕ ВІД `жорстке_ні` (тема-6), яке вже є: те — вільний текст по назві й
# крою, збіг підрядком. Це — СТРУКТУРОВАНІ ЗОНИ ТІЛА з порогом («ноги вище N см»), і
# воно мусить читати `відкрита_зона` та геометрію краю, а не назву. Річ може зватись
# «Спідниця класична» і відкривати ногу вище порога.
#
# ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after):
#   before — K-KOH-10 рахує КІЛЬКІСТЬ відкритих зон проти контексту і пропонує «лишити
#            одну». Тобто зона, яку людина не відкриває НІКОЛИ, конкурувала з іншими
#            за право бути тією єдиною. Особистого вето не існувало ніде.
#   after   — зона під вето не входить у набір узагалі; K-KOH-10 рахує лише те, що
#            лишилось. Регістр «гейт», сила hard, ремонт БЕЗ умовляння.
#
# ⚠ СИЛА hard ТУТ ЗАКОННА, ПОПРИ «сила ≤ верифікація»: це не емпіричне твердження про
# світ, яке треба доводити, а ПРИНЦИП — межа, яку встановила людина. Верифікувати
# нічого: доказом є те, що людина це сказала. Саме тому корпус позначає його
# «принцип·hard», а не «C·strong».
ЗОНИ_ПОКРИТТЯ = ("руки", "плечі", "декольте", "спина", "ноги", "живіт", "коліна")

def вето_покриття(E, вето=None, тіло=None):
    """K-PC-08. Речі, що порушують особисте вето покриття. Абсолютний фільтр.

    `вето`: {"зони": ["декольте","спина"], "ноги_вище_см": 45} — «ноги_вище_см»
    міряється ВІД ПІДЛОГИ (як і всі краї в посадка.py), тобто «поділ не вище N см
    від підлоги». Потребує `тіло` для перерахунку, коли поріг заданий від коліна.

    Повертає (чисті, знахідки). Знахідка — гейт: річ ПРИБИРАЄТЬСЯ, не понижується."""
    if not вето: return list(E), []
    зони = {str(z).strip().lower() for z in (вето.get("зони") or [])}
    поріг = вето.get("ноги_вище_см")
    чисті, зн = [], []
    for e in E:
        # ВЕТО ЧИТАЄ ВИВЕДЕНІ ЗОНИ, не лише заявлене поле. Доти воно спиралось на
        # `відкрита_зона`, яке НІХТО НЕ ПИСАВ — тобто правило сили `hard` на реальному
        # каталозі мовчало б завжди. Тепер зона виводиться з `виріз`, `тип`, назви й
        # геометрії краю (див. `зони_речі`).
        мої, чому_зон = зони_речі(e, тіло=тіло)
        перетин = sorted(мої & зони)
        # `коротко` — та сама гілка, що й `якщо`, але без чисел і без переліку
        # доказів: рівно те, що влазить у рядок промпту (див. блок нижче).
        якщо = коротко = None
        if перетин:
            якщо = ("відкриває %s, яку людина не відкриває (%s)"
                    % ("зону «%s»" % перетин[0] if len(перетин) == 1
                       else "зони %s" % ", ".join("«%s»" % z for z in перетин),
                       "; ".join(чому_зон)))
            коротко = ("відкриває %s — %s особистого вето, замінити"
                       % (", ".join("«%s»" % z for z in перетин),
                          "зону" if len(перетин) == 1 else "зони"))
        elif поріг is not None and e.get("низ_см") is not None \
                and e.get("слот") in ("низ", "сукня", "комплект"):
            if float(e["низ_см"]) > float(поріг):
                якщо = ("поділ на %.0f см від підлоги — вище особистої межі %.0f см"
                        % (float(e["низ_см"]), float(поріг)))
                коротко = "поділ вище особистої межі покриття — замінити на довше"
        if якщо is None:
            чисті.append(e); continue
        # ── ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026) ────────────────
        # before: «„Спідниця класична“ порушує вето покриття» — найсильніша сила
        # системи (hard, гейт) і при цьому речення, з якого не видно, ЩО саме в
        # речі порушує межу. А порушень тут два різні: відкрита зона й задовгий
        # поділ, — і ремонт у них різний. Все конкретне лежало в `чому` й `ремонт`,
        # тобто в полях, яких промпт ремонту не друкує; ші бачила вирок без складу.
        # after (два справжні рядки з двох прогонів):
        #   · «топ з відкритим вирізом»: відкриває «декольте» — зону особистого
        #     вето, замінити [1.00]
        #   · «спідниця міні»: поділ вище особистої межі покриття — замінити
        #     на довше [1.00]
        # Гілка не міняється: `коротко` заповнюється в тій самій розвилці, що й
        # `якщо`; ні порогу, ні сантиметрів у речення не пішло.
        зн.append(dict(_зн(
            "K-PC-08", "hard",
            "«%s»: %s" % (e.get("річ", e.get("id")), коротко),
            [e.get("річ") or e.get("id")],
            якщо + ". Це особиста межа, а не оцінка речі: обґрунтування не потрібне, "
                   "і система не пропонує спробувати",
            ремонт=["інша річ, що не відкриває цю зону"],
            запит=dict(слот=e.get("слот"), замість=e.get("річ"),
                       не_відкривати=sorted(зони) or None,
                       поділ_не_вище_см=поріг,
                       чому="K-PC-08: особисте вето покриття"),
            ламається="вето читає поле `відкрита_зона` і геометрію краю. Річ, яка "
                      "відкриває зону, але поля не несе, ПРОЙДЕ — це діра у ВХОДІ, "
                      "не в правилі, і вона видна в `без_поля_зони`"),
            # ТУТ СТОЯЛО `регістр="гейт", блокує=True` ПОВЕРХ `_зн` — четвертий із
            # чотирьох механізмів регістру (V23), знесений Н-02-05. Гейт лишається
            # той самий, але його тепер видає `регістр()` із єдиної таблиці:
            # `ПОЛІТИКА_РЕГІСТРУ["K-PC-08"]` = гейт з підставою `МЕЖА_ЛЮДИНИ`.
            # Це і є той випадок, який таблиця МУСИЛА вміти виразити: вето покриття
            # блокує за ПРИНЦИПОМ, а не за виміром, під ним нема жодної константи з
            # тіром, і вимагати її означало б відібрати в людини право на власну межу.
            # Корпус каже це прямо (тема-4:658, K-PER-05): сила `hard` «on the
            # person's authority alone», і правило стояло б незмінним, якби вся
            # цитована література зникла.
            сила_нп=1.0,
            сила_нп_джерело="принцип (не вимір): межу встановила людина"))
    return чисті, зн

def покриття_без_поля(E, тіло=None):
    """Скільки речей не дають ЖОДНОЇ підстави судити про зони — ні заявленої, ні
    виведеної. Це роздільна здатність K-PC-08, і вона мусить бути видною.

    ⚠ «Без підстав» ≠ «нічого не відкриває»: штани нічого не відкривають законно, а
    сукня без полів `виріз`/`назва` мовчить із незнання. Розрізнити їх можна лише за
    слотом, тому обидва числа повертаються окремо."""
    ризикові = ("верх", "сукня", "комплект", "низ", "верхній_шар")
    без, безпечні = [], []
    for e in E:
        з, чому = зони_речі(e, тіло=тіло)
        if з or чому: continue
        (без if e.get("слот") in ризикові else безпечні).append(
            e.get("річ") or e.get("id"))
    return dict(усього=len(E), без_підстав=len(без), приклади=без[:5],
                поза_ризиком=len(безпечні),
                чому="річ у слоті, що МОЖЕ відкривати зону, але без жодного поля, з "
                     "якого це виводиться (`виріз`, тип/назва, `низ_см`), проходить "
                     "вето мовчки. Частка таких і є стеля надійності K-PC-08")


# ── K-SIZ-02: НОМІНАЛЬНИЙ РОЗМІР — ЦЕ ПИТАННЯ, А НЕ ПОСАДКА ─────────────────
# КОРПУС (тема-7): «a nominal size does not predict fit»; CHANGES — «before: a size
# from the feed could become a fact about fit; after: a nominal size without garment
# measurements is a question, never a "fits"; the explanation shows the size as a
# range». FORCE `strong` для механізму, `hint` для КОЖНОГО числа — тому тут нема
# жодного порога: розкиди «≈10 см» / «≈12 см» корпус сам мітить `[folkloric]`, і
# ставити їх порогом заборонено за будь-якої сили.
#
# ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after, виміряно на `каталог_повний`).
#   before — мітка розміру в картці стоїть на 7 179 речах одягу з 8 589 (83.6 %),
#            і жоден шар її не читав: у вердикті про розмір не було ЖОДНОГО рядка.
#            Мовчання коду читається як «усе гаразд», і модель вільна написати
#            «сяде», бо ніхто не сказав їй, що номер цього не означає.
#   after  — на кожному образі, де мітка є, виходить ПИТАННЯ зі смугою («36–42»,
#            «XS–XL»), яке називає невизначеність і НЕ ранжує: регістр «питання»,
#            `блокує=False`, сила з категорії, бо виміру тут нема й бути не може.
#
# ЧОМУ ПИТАННЯ, А НЕ ВЕРДИКТ І НЕ ВОРОТА. Ворота відкинули б річ за те, чого код не
# знає (прецедент K-FIT-03 над дефолтним краєм: «вимір над заглушкою»); вердикт
# «сяде/не сяде» вимагав би обмірів виробу в сантиметрах, яких у каталозі нема
# (R-FEED-07). Лишається третій регістр, і він у системі вже є.
#
# ДВА СВІДКИ, НЕ ОДИН. Там, де магазин САМ каже «маломірить» (6 речей одягу й 28 пар
# взуття після зняття шаблону магазину — `feed.розмірність_речі`), питання перестає
# бути загальним: продавець уже заявив, що номер бреше, і це йде в те саме питання
# його словами, а не нашим переказом.
def розмір_не_посадка(речі, E=None):
    """K-SIZ-02: мітка розміру речі виходить ПИТАННЯМ зі смугою, а не фактом посадки.

    `E` — елементи стану; коли передані, питання стосується лише речей, ВИДНИХ у
    цьому стані (та сама конвенція, що в решті правил `review`: образ «надворі» і
    образ «у приміщенні» судяться окремо)."""
    import feed as _Ф
    # BREAKS корпусу дослівно: «when garment measurements in cm are present (then
    # `fit.тіло` works directly)». Поки обмірів нема (R-FEED-07), правило чинне;
    # щойно поле `обміри_см` з'явиться — питання замовкне само, бо посадку буде
    # чим порахувати. Предикат один на обидва правила й живе в `_вхід_є`, щоб
    # «без входу» називало те саме поле і в чеклісті, і тут.
    if E is not None and _вхід_є("обміри виробу в см", E, []):
        return []
    видимі = {e.get("річ") for e in (E or [])} if E is not None else None
    з_міткою = []
    for р in (речі or []):
        if р.get("слот") not in _Ф.СЛОТИ_РОЗМІРУ_ОДЯГУ:
            continue
        if видимі is not None and р.get("id") not in видимі:
            continue
        см = _Ф.смуга_розмірів(р)
        if см:
            з_міткою.append((р, см))
    if not з_міткою:
        return []
    каже = [(р, р["розмірність"]) for р, _ in з_міткою if р.get("розмірність")]
    нема = [(р, р["розміри_нема"]) for р, _ in з_міткою if р.get("розміри_нема")]
    чому = ("магазин назвав мітку розміру й не назвав обмірів виробу в сантиметрах. "
            "Без них номер не передбачає посадки: між магазинами та сама мітка "
            "стоїть на різних виробах, і наскільки різних — ніхто тут не міряв")
    if каже:
        чому += (". Про «%s» магазин сам каже «%s» — тобто заявляє, що номер його "
                 "власної шкали посадки не описує"
                 % ((каже[0][0].get("назва") or каже[0][0]["id"])[:40], каже[0][1]))
    if нема:
        чому += (". Частини міток у наявності нема (%s) — смуга ширша за те, що "
                 "справді можна купити" % ", ".join(нема[0][1]))
    з = _зн("K-SIZ-02", "питання",
            "розмір — це номер, не посадка: %s"
            % " · ".join("%s %s" % (р.get("слот"), см) for р, см in з_міткою),
            [р["id"] for р, _ in з_міткою], чому,
            ремонт=["приміряти або звірити обміри виробу з власними: номер сам по "
                    "собі відповіді не дає"],
            примітка="K-IO-05: правило цитується лише з атрибутом, який воно перевірило "
                     "— тут перевірено мітку, а не посадку")
    з["питання_людині"] = ("Який ваш звичний розмір у шкалі «%s» — і чи брали ви вже "
                           "щось у цьому магазині?" % з_міткою[0][1])
    з["навіщо"] = ("переведе K-SIZ-02 із питання у вимір і дасть пофірмовий зсув, "
                   "який корпус велить набирати з примірок і повернень, а не з досліджень")
    з["контракт"] = dict(поле="обміри_см",
                         звідки="сторінка товару або таблиця розмірів бренду "
                                "(R-ONT-09: її зішкрібають, фідом вона не приходить)")
    return [з]


# ── R-FP-07: КРІЙ — АТРИБУТ-ПРІЗВИСЬКО, І ДВОЄ СВІДКІВ ПРО НЬОГО МОВЧАЛИ ────
# КОРПУС (тема-7): «Nickname-class attributes are the highest-risk output: the
# reference model's own published failure is a wrong pocket nickname. Require a
# confidence signal on nickname outputs specifically, or drop the class»,
# FORCE `default`. Крій — рівно такий атрибут: «bodycon», «a-line», «wrap» —
# НАЗВА форми, а не її вимір.
#
# ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after, виміряно на `каталог_повний`).
#   before — у записі речі лежать ДВА свідчення про крій (слово крамниці й крій
#            із фото), і жоден шар їх не звіряє. `silhouette.КРОЇ` бере
#            переможця й переводить прізвисько в САНТИМЕТРИ (ease і форма —
#            множники обхвату), тобто здогад стає виміром без жодного сигналу
#            впевненості. Загальна `впевненість` запису тут не рятує: вона про
#            КОЛІР, не про крій.
