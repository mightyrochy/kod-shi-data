def спосіб(значення):
    """Значення перемикача → один із `СПОСОБИ`; невідоме або порожнє — `ТИПОВИЙ`."""
    з = str(значення or "").strip().lower()
    з = _ПСЕВДОНІМИ.get(з, з)
    return з if з in СПОСОБИ else ТИПОВИЙ


_Н = _re.compile(r"#?\s*(\d+)\s*[·.\-•:,]\s*(\d+)")


def ключ_н(x):
    """Номер речі в канонічній формі «#N·MM»: модель пише «12·03», «#12.03», «# 12-3»."""
    м = _Н.search(str(x or ""))
    return ("#%d·%02d" % (int(м.group(1)), int(м.group(2)))) if м else str(x or "").strip()


def _свої(r):
    """Річ, яку вибір не судить: її власна (закріплена) або названа її бажанням —
    її явний вибір сильніший за будь-який відбір (CLAUDE.md п.9)."""
    return bool(isinstance(r, dict) and (r.get("власна") or r.get("закріплена")
                                         or r.get("за_бажанням")))


def _контекст(пакет, межі=None):
    """Поля про неї для запиту — з пакета складання, а межі — з її слів (`межі`)."""
    к = {п.шлях: пакет.get(п.шлях) for п in _КОНТЕКСТ if пакет.get(п.шлях)}
    if межі:
        к["межі"] = межі
    return к


# ── ПОРЦІЇ Й ГРУПИ ───────────────────────────────────────────────────────────
def _порції(речі_слотів, скільки=РЕЧЕЙ_НА_ЗАПИТ):
    """{слот: [речі]} → список порцій {слот: [речі]} по ≤ `скільки` речей, слоти цілими,
    коли влазять; більший слот ріжеться на частини."""
    порції, поточна, n = [], {}, 0
    for с, рч in речі_слотів.items():
        рч = list(рч)
        while рч:
            місце = скільки - n
            if місце <= 0:
                порції.append(поточна); поточна, n = {}, 0
                continue
            шмат, рч = рч[:місце], рч[місце:]
            поточна.setdefault(с, []).extend(шмат); n += len(шмат)
    if поточна:
        порції.append(поточна)
    return порції


def групи_турніру(пул, сід):
    """{слот: [речі]} → {«слот·k»: [н…]}: слот перемішано сідом і поділено на групи
    по ≤ `ГРУПА_МАКС` (рівними, скільки дає ділення). Слот, у якому речей не більше
    за `ПЕРЕМОЖЦІВ`, групи не має: усі його речі проходять самі."""
    групи = {}
    for с, рч in пул.items():
        рч = [r for r in рч if not _свої(r)]
        if len(рч) <= ПЕРЕМОЖЦІВ:
            continue
        рч = _ПЗ.перемішати(рч, сід, "турнір|" + с)
        к = -(-len(рч) // ГРУПА_МАКС)
        розмір, лишок, поч = len(рч) // к, len(рч) % к, 0
        for і in range(к):
            кін = поч + розмір + (1 if і < лишок else 0)
            групи["%s·%d" % (с, і + 1)] = [x.get("н") for x in рч[поч:кін]]
            поч = кін
    return групи


# ── ЗАПИТИ ───────────────────────────────────────────────────────────────────
def _запит(оголошення, дані, сід, крок, чого, ключ, слоти=None, групи=None):
    """Один запит: текст збирачем + запис порядку для етапу руки."""
    текст = _json.dumps(_ЗП.зібрати(оголошення, дані), ensure_ascii=False, separators=(",", ":"))
    зап = _ПЗ.запис(сід, крок, слоти=слоти)
    if групи is not None:
        зап["групи"] = {г: [x.get("н") for x in рч] for г, рч in групи.items()}
    return dict(ключ=ключ, текст=текст, чого=чого, порядок=зап)


def запити_оцінки(пакет, чекають, сід_руки, раунд, межі=None):
    """Запити оцінки на речі `чекають` (множина «н»), порціями, кожна — своїм сідом."""
    пул = пакет.get("пул") or {}
    речі = {с: [x for x in рч if x.get("н") in чекають] for с, рч in пул.items()}
    речі = {с: рч for с, рч in речі.items() if рч}
    вих = []
    for і, порція in enumerate(_порції(речі)):
        сід = _ПЗ.сід_запиту(сід_руки, "оцінка", раунд, і)
        порція = _ПЗ.перемішати_слоти(порція, сід)
        вих.append(_запит(ОЦІНКА, dict(_контекст(пакет, межі), речі=порція), сід, "оцінка",
                          "оцінка речей · раунд %d · порція %d" % (раунд + 1, і + 1),
                          "о%d·%d" % (раунд + 1, і + 1), слоти=порція))
    return вих


def запити_турніру(пакет, групи, чекають, сід_руки, раунд, межі=None):
    """Запити турніру на групи `чекають`, порціями по ≤ `РЕЧЕЙ_НА_ЗАПИТ` речей."""
    за_н = {x.get("н"): x for рч in (пакет.get("пул") or {}).values() for x in рч}
    вих, порція, n = [], {}, 0

    def _закрити():
        """Порція груп → запит; порядок груп і речей у групі — сідом цього запиту."""
        сід = _ПЗ.сід_запиту(сід_руки, "турнір", раунд, len(вих))
        ключі = list(порція)
        if сід:
            _random.Random("%d|групи" % сід).shuffle(ключі)
        гр = {г: _ПЗ.перемішати(порція[г], сід, г) for г in ключі}
        вих.append(_запит(ТУРНІР, dict(_контекст(пакет, межі), групи=гр), сід, "турнір",
                          "турнір речей · раунд %d · порція %d" % (раунд + 1, len(вих) + 1),
                          "т%d·%d" % (раунд + 1, len(вих) + 1), групи=гр))

    for г in [г for г in групи if г in чекають]:
        рч = [за_н[н] for н in групи[г] if н in за_н]
        if n and n + len(рч) > РЕЧЕЙ_НА_ЗАПИТ:
            _закрити(); порція, n = {}, 0
        порція[г] = рч; n += len(рч)
    if порція:
        _закрити()
    return вих


# ── РОЗБІР ВІДПОВІДЕЙ ────────────────────────────────────────────────────────
def _карта_відповіді(текст, схема, поле):
    """Відповідь → (карта «ключ → значення» поля `поле`, причина провалу або None).

    Список пар [{н|ключ|група, …}] теж читається картою: це та сама відповідь іншою
    формою, і відкидати її означало б повторювати запит, на який модель відповіла."""
    об, причина, _нот = _ПР.розбір_за_схемою(текст, схема)
    if not isinstance(об, dict):
        return {}, причина or "відповідь не JSON-обʼєкт"
    к = об.get(поле)
    if isinstance(к, list):
        карта = {}
        for x in к:
            if isinstance(x, dict):
                ключ = x.get("н") or x.get("ключ") or x.get("група")
                знач = next((x[п] for п in ("оцінка", "код", "переможці", "н_переможців")
                             if п in x), None)
                if ключ is not None and знач is not None:
                    карта[str(ключ)] = знач
        к = карта
    if not isinstance(к, dict):
        return {}, "у відповіді нема поля «%s»" % поле
    return к, None


def прийняти_оцінки(стан, запитано, відповідь):
    """Одна відповідь оцінки → стан оновлено; вертає розбір для етапу руки."""
    карта, причина = _карта_відповіді(відповідь, "ОЦІНКИ_V1", "оцінки")
    свої = {ключ_н(к): v for к, v in карта.items()}
    оцінено, хибний_код = [], []
    for н in запитано:
        код = свої.pop(ключ_н(н), None)
        код = код.strip().lower() if isinstance(код, str) else код
        if код in КОДИ_ОЦІНКИ:
            стан["оцінки"][н] = код
            оцінено.append(н)
        elif код is not None:
            хибний_код.append(н)
    бракує = [н for н in запитано if н not in стан["оцінки"]]
    стан["вигадано"] = sorted(set(стан.get("вигадано") or []) | set(свої))
    return dict(чекало=len(запитано), оцінено=len(оцінено), бракує=бракує,
                хибний_код=хибний_код, вигадано=sorted(свої), причина=причина)


def прийняти_турнір(стан, запитано, відповідь):
    """Одна відповідь турніру → переможці груп у стан; розбір для етапу руки."""
    карта, причина = _карта_відповіді(відповідь, "ТУРНІР_V1", "переможці")
    свої = {str(к).strip(): v for к, v in карта.items()}
    вирішено, чужі = [], []
    for г in запитано:
        знач = свої.pop(г, None)
        знач = знач if isinstance(знач, list) else ([знач] if знач else [])
        члени = {ключ_н(н): н for н in стан["групи"].get(г, [])}
        п = []
        for x in знач:
            н = члени.get(ключ_н(x))
            if н is None:
                чужі.append(str(x))
            elif н not in п:
                п.append(н)
        if п:
            стан["переможці"][г] = п[:ПЕРЕМОЖЦІВ]
            вирішено.append(г)
    бракує = [г for г in запитано if г not in стан["переможці"]]
    return dict(чекало=len(запитано), вирішено=len(вирішено), бракує=бракує,
                чужі=чужі, вигадано=sorted(свої), причина=причина)


