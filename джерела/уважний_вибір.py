# Бази образу: сукня, комплект або верх із низом — ті самі, що визнає
# `суд_від_моделі.структура_образу`. Образи йдуть по колу баз, які мають придатні речі.
_БАЗИ = (("сукня",), ("комплект",), ("верх", "низ"))


def скласти_за_оцінками(пак, оцінки, сценарій=None, сід=0):
    """(ОБРАЗИ_V1 або None, звіт): образи, складені КОДОМ із речей, що «пасує».

    РІШЕННЯ ВЛАСНИКА 26.09 (варіант А): модель оцінює кожну річ, образ складає код за
    оцінками. Це НЕ повернення знесеного 31.08 перебору композитора: той образи вигадував
    сам, а тут код лише розкладає вже схвалені моделлю речі по структурі образу.
    ЯК: база — по колу `_БАЗИ` з тих, що мають придатні речі (її закріплена річ задає
    базу сама); у кожному слоті — придатна річ, яку взяли найменше разів (рівні — у
    порядку показу), тож образи різняться; обов'язкові слоти пакета (взуття, сумка,
    верхній шар) — так само; структурну діру, яку лишив цей розклад (третя річ, пальто),
    закриває `повнота_образу._дібрати_кодом` з тих самих придатних речей. Її бажання й
    закріплена річ «пасує» за означенням (`_свої`). Кольорів код не зводить: образ судить
    той самий суд, що й образ моделі, і ремонт (модель) лагодить знайдене."""
    import пакет_моделі as _PM
    import повнота_образу as _ПО
    пакет = пак.get("пакет") or {}
    кандидати = пак.get("кандидати") or {}
    ном, _ = _PM.номери_речей(кандидати)
    н_ід = {"#%d·%s" % v: к for к, v in ном.items()}
    ід_н = {к: н for н, к in н_ід.items()}
    словник = {r.get("id"): dict(r, слот=с) for с, рч in кандидати.items() for r in рч}
    придатні = {}
    for с, рч in (пакет.get("пул") or {}).items():
        for x in _ПЗ.перемішати(рч, сід, "склад|" + с):
            r = словник.get(н_ід.get(x.get("н")))
            if r is None:
                continue
            if _свої(r) or оцінки.get(x.get("н")) == ПАСУЄ:
                придатні.setdefault(с, []).append(r)
    обм = пакет.get("обмеження") or {}
    обов = [с for с in (обм.get("обов'язкові_слоти") or []) if придатні.get(с)]
    закр = {н_ід.get(ключ_н(н)) for н in (обм.get("закріплені") or [])} - {None}
    закр_сл = {словник[і]["слот"]: і for і in закр if і in словник}
    бази = [б for б in _БАЗИ if all(придатні.get(с) for с in б)]
    if закр_сл:
        свої_бази = [б for б in бази if set(б) & set(закр_сл)]
        бази = свої_бази or бази
    звіт = dict(оцінено=len(оцінки), пасує=sum(1 for v in оцінки.values() if v == ПАСУЄ),
                причини={к: sum(1 for v in оцінки.values() if v == к) for к in КОДИ_ОЦІНКИ
                         if к != ПАСУЄ and any(v == к for v in оцінки.values())},
                придатних={с: len(v) for с, v in придатні.items()}, бази=[], дібрано=0)
    if not бази:
        звіт["чому"] = "жодної бази образу (сукня, комплект, верх із низом) серед речей, що «пасує»"
        return None, звіт
    варіантів = int(((пакет.get("завдання") or {}).get("образів")) or 1)
    вжито = {}
    образи = []
    for k in range(варіантів):
        база = бази[k % len(бази)]
        ід = [закр_сл[с] for с in закр_сл]
        for с in list(база) + обов:
            if с in закр_сл or any(словник[і]["слот"] == с for і in ід):
                continue
            вільні = [r for r in придатні.get(с, []) if r["id"] not in ід]
            if вільні:
                r = min(вільні, key=lambda r: вжито.get(r["id"], 0))
                ід.append(r["id"])
        # структурна діра (третя річ, пальто) — з тих самих придатних речей, по колу від k
        кола = {с: (рч[k % len(рч):] + рч[:k % len(рч)]) for с, рч in придатні.items() if рч}
        дібр, додано, _чому = _ПО._дібрати_кодом(ід, {}, кола, словник, сценарій)
        if додано:
            ід = дібр
            звіт["дібрано"] += len(додано)
        for і in ід:
            вжито[і] = вжито.get(і, 0) + 1
        звіт["бази"].append("+".join(база))
        образи.append({"ід": "о%d" % (k + 1), "полюс": _ПР.ПОЛЮС_ВІЛЬНИЙ,
                       "речі": [ід_н.get(і, і) for і in ід]})
    return {"версія": _ПР.ВЕРСІЯ, "образи": образи}, звіт


def пакет_фіналу(пакет, переможці, сід):
    """(ПАКЕТ_V1 фіналу, запис порядку): той самий пакет складання, пул — лише переможці
    груп, речі слотів без турніру (≤ `ПЕРЕМОЖЦІВ`) і її власні/бажані речі (`_свої`)."""
    пройшли = {н for п in переможці.values() for н in п}
    п = _copy.deepcopy(пакет)
    пул = {}
    for с, рч in (пакет.get("пул") or {}).items():
        без_турніру = len([r for r in рч if not _свої(r)]) <= ПЕРЕМОЖЦІВ
        лишаються = [r for r in рч if без_турніру or _свої(r) or r.get("н") in пройшли]
        if лишаються:
            пул[с] = _ПЗ.перемішати(лишаються, сід, с)
    п["пул"] = пул
    return п, _ПЗ.запис(сід, "складання", слоти=пул)


# ── ГОЛОВНИЙ ВХІД ────────────────────────────────────────────────────────────
def крок(вхід, пак, сценарій=None, сід_руки=0, межі=None):
    """Один крок уважного вибору: {спосіб, стан?, відповіді?} → {готово, запити, стан,
    розбір, звіт, текст_складання | промпт_фіналу, порядок_фіналу}.

    Перший крок (стану нема) — усі речі (А) чи всі групи (Б) чекають. Далі кожна
    відповідь розбирається проти ТОГО запиту, на який вона відповідала (`стан.запитано`);
    що лишилось без оцінки чи переможців — іде наступним раундом, доки раундів не
    `СПРОБ_ПОВНОТИ` + 1. Потім фініш: чого модель так і не оцінила, у складання не йде
    (А), а група без переможців проходить ЦІЛОЮ (Б) — обидва названо у звіті."""
    вхід = dict(вхід or {})
    с = спосіб(вхід.get("спосіб"))
    пакет = (пак or {}).get("пакет") or {}
    if с == ТИПОВИЙ or not пакет.get("пул"):
        return dict(спосіб=с, готово=True, запити=[], чому="спосіб «%s» — складання як доти" % с)
    стан = вхід.get("стан") or {}
    розбір = {}
    if not стан:
        н_усі = [x.get("н") for рч in пакет["пул"].values() for x in рч if not _свої(x)]
        if с == "оцінка":
            стан = dict(спосіб=с, раунд=0, оцінки={}, чекають=н_усі, запитано={}, вигадано=[])
        else:
            групи = групи_турніру(пакет["пул"], _ПЗ.сід_запиту(сід_руки, "турнір"))
            стан = dict(спосіб=с, раунд=0, групи=групи, переможці={}, чекають=list(групи),
                        запитано={}, вигадано=[])
    else:
        for в in (вхід.get("відповіді") or []):
            ключ = str((в or {}).get("ключ") or "")
            запитано = (стан.get("запитано") or {}).get(ключ) or []
            розбір[ключ] = (прийняти_оцінки if с == "оцінка" else прийняти_турнір)(
                стан, запитано, (в or {}).get("текст"))
        if с == "оцінка":
            стан["чекають"] = [н for н in стан["чекають"] if н not in стан["оцінки"]]
        else:
            стан["чекають"] = [г for г in стан["чекають"] if г not in стан["переможці"]]
        стан["раунд"] = int(стан.get("раунд") or 0) + 1
    if стан["чекають"] and стан["раунд"] <= СПРОБ_ПОВНОТИ:
        if с == "оцінка":
            запити = запити_оцінки(пакет, set(стан["чекають"]), сід_руки, стан["раунд"], межі)
            стан["запитано"] = {з["ключ"]: [н for рч in з["порядок"]["слоти"].values() for н in рч]
                                for з in запити}
        else:
            запити = запити_турніру(пакет, стан["групи"], set(стан["чекають"]), сід_руки,
                                    стан["раунд"], межі)
            стан["запитано"] = {з["ключ"]: list(з["порядок"]["групи"]) for з in запити}
        if запити:
            return dict(спосіб=с, готово=False, запити=запити, стан=стан, розбір=розбір)
    # ── ФІНІШ ──
    if с == "оцінка":
        образи, звіт = скласти_за_оцінками(пак, стан["оцінки"], сценарій,
                                           _ПЗ.сід_запиту(сід_руки, "склад"))
        звіт.update(не_оцінено=list(стан["чекають"]), вигадано=list(стан.get("вигадано") or []),
                    раундів=стан["раунд"])
        return dict(спосіб=с, готово=True, запити=[], стан=стан, розбір=розбір, звіт=звіт,
                    текст_складання=(_json.dumps(образи, ensure_ascii=False) if образи else None))
    for г in стан["чекають"]:
        стан["переможці"][г] = list(стан["групи"][г])    # група без переможців — цілою
    фінал, пор = пакет_фіналу(пакет, стан["переможці"], _ПЗ.сід_запиту(сід_руки, "фінал"))
    звіт = dict(груп=len(стан["групи"]), без_переможців=list(стан["чекають"]),
                у_фіналі=sum(len(v) for v in фінал["пул"].values()),
                було=sum(len(v) for v in пакет["пул"].values()), раундів=стан["раунд"])
    return dict(спосіб=с, готово=True, запити=[], стан=стан, розбір=розбір, звіт=звіт,
                промпт_фіналу=_json.dumps(фінал, ensure_ascii=False, separators=(",", ":")),
                порядок_фіналу=пор)


def прогнати(спосіб_, пак, модель, сід_руки, сценарій=None, межі=None):
    """Увесь уважний вибір без показу — для проби стабільності й ноутбука.

    `модель(текст) → текст`. → (фініш `крок`, обрані): `обрані` — [(номер, місце, довжина)]
    для кожної речі, яку спосіб ОБРАВ моделлю: оцінка — «пасує»; турнір — переможець
    групи (група, що пройшла цілою, — не вибір моделі й не рахується); місце — індекс
    у тому переліку, яким річ стояла в запиті (слот порції, група турніру)."""
    вр = крок({"спосіб": спосіб_}, пак, сценарій, сід_руки, межі)
    місця = {}
    while not вр.get("готово"):
        відп = []
        for з in вр.get("запити") or []:
            пор = з.get("порядок") or {}
            for перелік in (пор.get("групи") or пор.get("слоти") or {}).values():
                for і, н in enumerate(перелік):
                    місця[н] = (і, len(перелік))
            відп.append({"ключ": з["ключ"], "текст": модель(з["текст"])})
        вр = крок({"спосіб": спосіб_, "стан": вр.get("стан"), "відповіді": відп},
                  пак, сценарій, сід_руки, межі)
    стан = вр.get("стан") or {}
    if спосіб(спосіб_) == "оцінка":
        обрані = [н for н, к in (стан.get("оцінки") or {}).items() if к == ПАСУЄ]
    else:
        цілі = set((вр.get("звіт") or {}).get("без_переможців") or [])
        обрані = [н for г, п in (стан.get("переможці") or {}).items() if г not in цілі for н in п]
    return вр, [(н,) + місця[н] for н in обрані if н in місця]

