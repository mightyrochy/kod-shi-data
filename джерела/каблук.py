# -*- coding: utf-8 -*-
"""Каблук з тексту каталогу: клас, форма, висота — і ЗВІДКИ це відомо.

ЩО ЦЕ МІНЯЄ В РЕАЛЬНОМУ РІШЕННІ (правило 3, before/after).
Випадок: тестувальниця просить «взуття на тонких підборах».
  before — пул взуття 228 речей, з них кеди, кросівки, лофери й балетки; жодне
           поле про каблук не існує, модель обирає за назвою й видає мюлі,
           описуючи їх «на округлих скульптурних підборах» — атрибут, якого в
           каталозі нема ЗОВСІМ. Вердикт носія стосується вигаданої речі.
  after  — 664 речі з 1117 мають клас «нема» ВИЗНАЧЕННЯМ (балетка з каблуком не
           балетка) і зникають з пулу під цю вимогу; речі з класом «є» видно
           окремо; речі без даних лишаються в пулі, але несуть мітку «каблук не
           оголошений» — і модель не має права стверджувати про них форму.

СИЛА ≤ ВЕРИФІКАЦІЯ (правило 4). Три різні регістри, і вони не змішуються:
  · `визначення` — категорія виключає каблук за побудовою (балетки, кеди,
    кросівки, лофери, мокасини, шльопанці, топсайдери). Це hard: тут нема
    статистики, є значення слова.
  · `назва` — у назві стоїть саме слово («kitten heels», «на підборах»).
    Теж hard, але покриття мізерне: 19 речей з 1117.
  · `невідомо` — усе інше (≈380 речей: туфлі, босоніжки, мюлі, слінгбеки,
    черевики, чоботи, сабо). Це НЕ «звичайний каблук за замовчуванням».
    Мовчання ≠ пройдено: невідоме називається невідомим.

ЧОГО ТУТ НЕМА І ЧОМУ. Висоти в сантиметрах нема ні в одної речі: у каталозі
нуль `<param>` про каблук, нуль `Заміри` для взуття, нуль чисел «см» у назвах,
і `<description>` у фіді відсутній як тег. Єдине джерело, яке лишається, —
фото речі; воно потребує передачі URL зображень у модель (окрема робота) і тут
не робиться. Вигадати висоту з типу («туфлі ≈ 7 см») означало б поставити
число там, де виміру нема, — рівно те, що забороняє «сила ≤ верифікація».
"""
import re

# Ключі ЗОВНІШНЬОГО контракту: їх пише не наш код, а фід (жниварка).
# Декларація стоїть у модулі, а не в сканері: інакше під загальним списком
# сховається справжня сирота (див. `audit_contracts`, розділ 1b).
ЗОВНІШНІ_ВХОДИ = {
 "звідки_взято": "розділ лістингу з фіду: разом зі слагом url тримає шлях категорії,\n                  за яким клас каблука визначається без назви",
}

# ── КАТЕГОРІЇ, ЯКІ ВИКЛЮЧАЮТЬ КАБЛУК ВИЗНАЧЕННЯМ ───────────────────────────
# Не «зазвичай плоскі», а «з каблуком це вже інша річ». Саме тому сила hard.
ПЛОСКІ = (
    r"балетк", r"\bballet\b", r"ballet-flats",
    r"лофер", r"\bloafer", r"мокасин", r"moccasin",
    r"кед[иіауи]\b", r"\bkedy\b", r"кросівк", r"krosivk", r"krossovk",
    r"\bsneaker", r"woman-sneakers", r"сліпон", r"slip-on",
    r"шльопанц", r"shlyepants", r"в['’]єтнамк", r"\bflip", r"flipflop", r"сланц",
    r"топсайдер", r"topsayder", r"\bespadril", r"еспадрил",
)

# ── КАТЕГОРІЇ, ЯКІ ВИМАГАЮТЬ КАБЛУКА ВИЗНАЧЕННЯМ ───────────────────────────
# «Човник» (pump) без каблука — не човник. Форма й висота лишаються невідомі.
З_КАБЛУКОМ = (r"човник", r"\bpumps?\b", r"/pumps/")

# ── СЛОВА, ЯКІ НАЗИВАЮТЬ САМ КАБЛУК ────────────────────────────────────────
# Порядок має значення: конкретніше слово перекриває загальніше.
СЛОВА = (
    (r"шпильк|стилет|stilett?o",            dict(є=True, форма="тонкий",  висота="високий")),
    # ПАСТКА ПІДРЯДКА, спіймана виміром: «китн» лежить усередині «бла-КИТН-і»,
    # і дев'ять блакитних кедів, кросівок та балеток діставали клас «тонкий
    # каблук». Транслітерація лишається, але з межею слова.
    (r"kitten[\s-]*heels?|\bкіттен|\bкітн\w*\s*(каблук|підбор)",
                                            dict(є=True, форма="тонкий",  висота="низький")),
    (r"платформ|platform",                  dict(є=True, форма="товстий", висота=None)),
    (r"танкетк|\bwedge",                    dict(є=True, форма="товстий", висота=None)),
    (r"блочн\w*\s*(каблук|підбор)|block[\s-]*heel",
                                            dict(є=True, форма="товстий", висота=None)),
    (r"тонк\w*\s*(каблук|підбор)",          dict(є=True, форма="тонкий",  висота=None)),
    (r"висок\w*\s*(каблук|підбор)",         dict(є=True, форма=None,      висота="високий")),
    (r"низьк\w*\s*(каблук|підбор)",         dict(є=True, форма=None,      висота="низький")),
    (r"на\s+підбор|на\s+каблу|каблук|підбор", dict(є=True, форма=None,    висота=None)),
)

ПОРОЖНІЙ = dict(є=None, форма=None, висота=None, джерело=None, сила=None)


def _текст(назва, параметри=None, url=None):
    """Усе, що каталог каже про річ словами: назва + тип + розділ лістингу + url.

    Розділ лістингу (`звідки_взято`) і слаг url — не декор: у welfare.ua шлях
    несе `/female-shoes/ballet-flats/`, а назва — лише артикул. Без цих двох
    полів 24 балетки читались би як «невідомо».
    """
    п = параметри or {}
    ч = [назва or "", п.get("тип") or "", п.get("звідки_взято") or "",
         url or п.get("джерело_url") or ""]
    return " ".join(ч).lower()


def каблук(назва, параметри=None, url=None):
    """dict(є, форма, висота, джерело, сила). `є=None` — НЕ «нема», а «не знаю»."""
    т = _текст(назва, параметри, url)
    if not т.strip():
        return dict(ПОРОЖНІЙ)
    # 1. пряме слово в тексті — найсильніше, бо каже саме про каблук
    for пат, знач in СЛОВА:
        if re.search(пат, т):
            return dict(знач, джерело="назва", сила="hard")
    # 2. категорія, яка виключає каблук визначенням
    for пат in ПЛОСКІ:
        if re.search(пат, т):
            return dict(є=False, форма=None, висота=None,
                        джерело="визначення", сила="hard")
    # 3. категорія, яка вимагає каблука визначенням
    for пат in З_КАБЛУКОМ:
        if re.search(пат, т):
            return dict(є=True, форма=None, висота=None,
                        джерело="визначення", сила="hard")
    return dict(ПОРОЖНІЙ)


def словами(к):
    """Рядок для моделі й для людини. Невідоме називається невідомим."""
    if not к or к.get("є") is None:
        return "каблук не оголошений"
    if к["є"] is False:
        return "без каблука"
    ч = [x for x in (к.get("форма"), к.get("висота")) if x]
    return "каблук: " + (" · ".join(ч) if ч else "є, форма не оголошена")


# ── ФІЛЬТР ПІД ПРОХАННЯ ЛЮДИНИ ─────────────────────────────────────────────
# ЩО ЦЕ МІНЯЄ: єдине місце, де прохання про взуття стає ВІДБОРОМ, а не реченням
# у промпті. Без нього «взуття на тонких підборах» лишається побажанням, яке
# модель виконує з пулу, де 59 % речей каблука не мають за побудовою.
ПРОХАННЯ = (
    (r"тонк\w*\s*(підбор|каблук)|шпильк|стилет|kitten", "тонкий"),
    (r"висок\w*\s*(підбор|каблук)", "високий"),
    (r"на\s+підбор|на\s+каблу|з\s+каблук", "є"),
    (r"без\s+підбор|без\s+каблук|плоск\w*\s*(підошв|взутт)|кросівк|кед[иі]", "нема"),
)


def прохання(вимоги):
    """Що саме людина попросила про взуття. None — не просила нічого."""
    т = (вимоги or "").lower()
    if not т.strip():
        return None
    for пат, код in ПРОХАННЯ:
        if re.search(пат, т):
            return код
    return None


def відсів(речі, запит, поле=None):
    """(лишилось, вибуло, чому) — відбір взуття під прохання людини.

    ЖОРСТКО ВИКИДАЄТЬСЯ ЛИШЕ ТЕ, ЩО СУПЕРЕЧИТЬ ВИЗНАЧЕННЯМ. Річ із невідомим
    каблуком лишається в пулі: «не оголошено» — не «не підходить». Викинути її
    означало б зробити 380 речей невидимими на підставі мовчання магазину.
    """
    if not запит:
        return list(речі), [], "прохання про взуття не було"
    лиш, геть = [], []
    for r in речі:
        є = (r.get(поле) or ПОРОЖНІЙ).get("є") if поле else r.get("каблук_є")
        if запит in ("тонкий", "високий", "є"):
            погано = (є is False)
        else:                       # запит == "нема"
            погано = (є is True)
        (геть if погано else лиш).append(r)
    чому = ("прохання «%s»: %d речей суперечать визначенням і зняті, %d лишились "
            "(з них %d без оголошеного каблука)"
            % (запит, len(геть), len(лиш),
               sum(1 for r in лиш
                   if ((r.get(поле) or ПОРОЖНІЙ).get("є") if поле else r.get("каблук_є")) is None)))
    return лиш, геть, чому
