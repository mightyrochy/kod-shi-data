# ── ЗАПИС: ТЕКСТОВА ХІРУРГІЯ, НЕ ПЕРЕСЕРІАЛІЗАЦІЯ ────────────────────────────
# ET.write() перепише ВЕСЬ файл: порядок атрибутів, самозакриття, екранування.
# Тоді diff у git — 10 МБ, і жодна правка не піддається огляду. Тому офери
# ріжуться й правляться на рівні тексту.
# ЩО САМЕ ЛИШАЄТЬСЯ БАЙТ У БАЙТ (виправлено 10.09.2026). Обіцянка «решта файла»
# була хибною: два глобальні replace() по всьому `вих` правили 671 місце, тоді
# як адресних правок — 304 офери, а видалень — 21. Обіцянка «байт у байт» —
# єдина причина, чому тут текстова хірургія замість ET.write, і саме на неї
# спирається огляд diff. Тепер розекранування йде ВСЕРЕДИНІ циклу, по офера́х, і
# байт у байт лишається все, чого чистка не оголосила своєю правкою: текст поза
# оферами (на `каталог_повний.xml` там 0 із 671 місця) і кожен офер без жодного
# з ТРЬОХ класів правок — видалення, слот, екранування.
# ЕКРАНУВАННЯ — ОГОЛОШЕНИЙ КЛАС, А НЕ ПОБІЧНА ДІЯ: воно правиться в усіх оферах
# навмисно (307 `<picture>` несуть `&amp;amp;h=1200`, тобто зламане посилання на
# фото, а не косметику назви) і рахується окремим полем `екранувань_виправлено`.
# ID НЕ УНІКАЛЬНИЙ (1 230 пар «ж-00237» у різних магазинах, пам'ять 28.08),
# тож офери адресуються ПОРЯДКОВИМ НОМЕРОМ, який збігається з ET.iter.
# ЄДИНЕ, ЩО ПРАВИТЬСЯ ПОЗА ОФЕРАМИ, — блок <categories>, і лише дописом: коли
# каталог не має категорії з іменем цільового слота (формат жниварки v4.0),
# без неї правка слота лишилась би наполовину зробленою. Число дописаних іде
# у відповідь полем `категорій_дописано`, а не мовчки.
# ═══ ВІДНОВЛЕНА НАЗВА В САМОМУ КАТАЛОЗІ (рядок 182, 24.09.2026) ═══════════
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. Доти слот і тип читались із СИРОЇ назви фіду, навіть
# коли картка вже показувала жінці відновлену («Обруч Блер чорний» замість
# «Носіть його з чорною крихітною сукнею…»). Тепер відновлена назва рахується
# ТУТ, раз на каталог, і лягає в оффер параметром — далі її читають обидва:
# класифікатор (`фід_слот`) і картка (`міст_опис`).
#
# ЧОМУ В КАТАЛОЗІ, А НЕ НА ЛЬОТУ: `назва_речі.назва_для_показу` коштує 6.45 с на
# 11 993 оферів (вимір 24.09.2026) — +111 % до `читати_yml`. У Pyodide на
# телефоні це помітно; офлайн, у чистці, це не коштує нічого, бо чистка й так
# читає весь файл.
#
# СВІДОК СВІЖОСТІ — МАРКЕР, А НЕ ПЕРЕРАХУНОК. `_брудність` кличеться на КОЖНОМУ
# читанні каталогу (`фід_каталог.каталог_на_диску`), тож рахувати там назви
# заново означало б платити ті самі 6.45 с щоразу. Замість того у файл лягає
# один рядок-маркер із версією; не збігається версія або нема маркера — каталог
# лежалий, і чистка проходить його повністю.
_МАРКЕР_НАЗВ = re.compile(r"<!--\s*назва_показу:\s*версія\s*(\d+)\s*,\s*речей\s*(\d+)\s*-->")
_ПАРАМ_НАЗВИ_РЕ = re.compile(
    r'\s*<param name="(?:%s)">[^<]*</param>'
    % "|".join((назва_речі.ПАРАМ_НАЗВИ, назва_речі.ПАРАМ_ДЖЕРЕЛА_ПОКАЗУ,
                назва_речі.ПАРАМ_ПРИЧИНИ)))
_КІНЕЦЬ_ОФЕРА = re.compile(r"\s*</offer>\s*$")


def _екранувати_параметр(текст):
    """Значення параметра у XML: лише ті п'ять символів, що ламають розбір."""
    return (str(текст).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace('"', "&quot;").replace("'", "&apos;"))


def _вписати_назву(текст_офера, назва, джерело, причина):
    """Оффер із параметрами відновленої назви (назва, джерело, причина) замість старих.

    Старі знімаються завжди — інакше повторна чистка з новою версією лишила б
    поруч два значення, і `читати_yml` взяв би останнє, не знаючи, котре свіже.
    ПРИЧИНА («речення», «нема назви речі», «розділ», «чужа мова»…) їде разом із
    назвою: її читає звіт власника, і після офлайн-рахунку відновити її нема з чого."""
    текст = _ПАРАМ_НАЗВИ_РЕ.sub("", текст_офера)
    if not назва:
        return текст
    поля = ((назва_речі.ПАРАМ_НАЗВИ, назва),
            (назва_речі.ПАРАМ_ДЖЕРЕЛА_ПОКАЗУ, джерело),
            (назва_речі.ПАРАМ_ПРИЧИНИ, причина))
    вставка = "".join('    <param name="%s">%s</param>\n' % (к, _екранувати_параметр(з))
                      for к, з in поля if з) + "  </offer>"
    return _КІНЕЦЬ_ОФЕРА.sub("\n" + вставка, текст)


def _назви_лежалі(шлях, сирий=None):
    """Скільки оферів чекають на відновлену назву. 0 — маркер свіжий, рахувати нема чого.

    Число НЕ точне і точним бути не мусить: це свідок «каталог не проходив
    поточної версії відновлення», а не лічба речей. Точну лічбу робить
    `почистити`, і вона ж пише маркер."""
    т = сирий if сирий is not None else open(шлях, encoding="utf-8").read()
    м = _МАРКЕР_НАЗВ.search(т)
    if м and int(м.group(1)) == назва_речі.ВЕРСІЯ_ВІДНОВЛЕННЯ:
        return 0
    return т.count("<offer ")


_OFFER = re.compile(r"<offer\b.*?</offer>", re.S)
_CATEGORY_ID = re.compile(r'<category\b[^>]*\bid="(\d+)"')
_КІНЕЦЬ_КАТЕГОРІЙ = "</categories>"


def _дописати_категорії(сирий, ціль_id):
    """Категорії для слотів, яких у файлі нема, — тим самим текстовим шматком.

    ЧОМУ ЦЕЙ ШЛЯХ, А НЕ «правити лише param «слот»» (вимір 10.09.2026). У
    `feed.слот` категорія-ЛИСТ переважує param, коли вона сама є іменем слота:
    `_оголош = (_лист if _лист in ІМЕНА_СЛОТІВ else параметри["слот"])`. Старий
    каталог — саме такий: усі 11 категорій `каталог_повний.xml` є іменами
    слотів. Тож правка лише param лишила б усі 304 помилки слота на місці
    (перевірено: категорія «сукня» + param «низ» → `feed.слот` віддає «сукня»).
    Правити треба обидва оголошення, а для цього цільова категорія мусить у
    файлі БУТИ. На форматі жниварки v4.0 категорія — шлях магазину, тож імені
    слота серед них нема; дописуємо його з новим id = max(існуючих) + 1.

    Мутує `ціль_id` на місці: дописаний слот дістає свій новий id.
    Повертає (сирий, скільки_дописано)."""
    бракує = sorted(с for с, і in ціль_id.items() if і is None)
    if not бракує:
        return сирий, 0
    п = сирий.find(_КІНЕЦЬ_КАТЕГОРІЙ)
    if п < 0:
        return сирий, 0          # нема куди дописувати — відмова нижче, з текстом
    вільний = max((int(x) for x in _CATEGORY_ID.findall(сирий[:п])), default=0) + 1
    шматок = ""
    for с in бракує:
        ціль_id[с] = str(вільний)
        шматок += '<category id="%s">%s</category>' % (вільний, с)
        вільний += 1
    return сирий[:п] + шматок + сирий[п:], len(бракує)


# ── ОДИН ШЛЯХ ДО ЧИСТОГО КАТАЛОГУ НА ДИСКУ (19.09.2026, рядок 57 дошки) ──────
# ЩО ЦЕ ЛАГОДИТЬ. Чистка жила ЛИШЕ окремим кроком CI («розпакувати каталоги й
# почистити фід» у `zbirka.yml`), а `build_артефакт` на брудному каталозі
# відмовлявся й друкував ту саму команду як пораду. Тобто шляхів до продукту
# було два, і той, яким ходить людина, червоний ЗА ПОБУДОВОЮ: у свіжому
# checkout збірка падала з «каталог_повний.xml БРУДНИЙ — помилок слота 325,
# подвійних екранувань 24» — виміряно двома сесіями 19.09.2026, стабільно на
# 1-му й 2-му прогоні, тоді як CI на тому самому дереві зелений. Кожна нова
# сесія витрачала час на розгадування вже розгаданого.
# ЧОМУ МОЖНА ЧИСТИТИ САМІЙ, А НЕ ЛИШЕ ВІДМОВЛЯТИ. `почистити` детермінована
# (ні часу, ні випадку, ні мережі) і ідемпотентна: другий виклик на власному
# виході дає «видалено 0, слотів_виправлено 0, екранувань_виправлено 0» — тобто
# збірка, яка чистить сама, робить рівно те саме, що робив крок CI, і другий раз
# не робить нічого. Розпакований каталог у git не їде (`.gitignore`), тож правка
# НА МІСЦІ нічого не псує: чистимо робочу копію, а не джерело.
# ФІКСТУРА СЮДИ НЕ ХОДИТЬ: у `каталог_brief.xml` помилки слота стоять НАВМИСНО
# (§40), і викликач (`build_артефакт._зібрати_zip_лайт`) відрізає її до виклику.
def _брудність(шлях):
    """(помилок слота, подвійних екранувань, мовних двійників, лежалих назв) — числа гейта збірки.

    Третє число додано рядком 144 (23.09.2026): без нього чистка не вмикалась би
    на каталозі, де слот і екранування вже чисті, а той самий товар лежить двічі —
    українською й англійською. Четверте — рядком 182 (24.09.2026): каталог без
    маркера поточної версії відновлення несе слот і тип, прочитані з назви, якої
    жінка на картці вже не бачить. Це свідок за МАРКЕРОМ, а не перерахунок назв:
    `_брудність` кличеться на кожному читанні каталогу, і 6.45 с там коштували б
    дорожче за все, що вони ловлять."""
    дерево, корінь, _, _, помилки, _, _, _ = класифікувати(шлях)
    return (len(помилки), open(шлях, "rb").read().count(b"&amp;quot;"),
            len(мовні_двійники(корінь)), _назви_лежалі(шлях))


# РЯДОК 89 (20.09.2026): `фід_каталог.каталог_на_диску` тепер сама кличе цю
# функцію на кожному резольвленому шляху (крім фікстури) — свіже дерево без
# збірки і збірка дають ОДИН каталог, не два. `_шлях` — для того виклику: шлях
# уже знайдено, і друге звернення до `feed.каталог_на_диску` тут дало б
# нескінченну рекурсію (той шлях веде назад у `каталог_на_диску`). Кеш за
# абсолютним шляхом — щоб build (спершу `_розпакувати_каталог`, потім свій
# `забезпечити_чистим`) не парсив ті самі 45 МБ XML двічі в одному процесі;
# зберігаємо ПОВНИЙ результат, а не прапорець, — щоб друга звірка бачила ті самі
# «до» числа, що й перша, а не «нічого чистити».
_КЕШ_ЧИСТКИ = {}


def забезпечити_чистим(ім=None, тека=None, _шлях=None):
    """Каталог НА ДИСКУ і ЧИСТИЙ: розпакувати з `.gz` за потреби, почистити за потреби.

    Розпаковує тим самим і єдиним розпаковувачем, що й прилади
    (`feed.каталог_на_диску`), а чистить на місці. Повертає числа ДО і ПІСЛЯ,
    щоб викликач надрукував ФАКТ, а не «ок».
    Відмовляє лише тоді, коли після чистки бруд ЛИШИВСЯ, — це вже не звичка
    середовища, а дефект даних або самої чистки, і мовчати про нього не можна."""
    шлях = _шлях if _шлях is not None else feed.каталог_на_диску(ім, тека)
    шлях_абс = os.path.abspath(шлях)
    if шлях_абс in _КЕШ_ЧИСТКИ:
        return _КЕШ_ЧИСТКИ[шлях_абс]
    помилок, екранувань, двійників, лежалих = _брудність(шлях)
    if not помилок and not екранувань and not двійників and not лежалих:
        р = dict(шлях=шлях, помилок_до=0, екранувань_до=0, двійників_до=0, лежалих_назв_до=0,
                 почищено=False, звіт=None)
        _КЕШ_ЧИСТКИ[шлях_абс] = р
        return р
    звіт = почистити(шлях, шлях)
    лишилось, лишилось_екр, лишилось_дв, лишилось_назв = _брудність(шлях)
    if лишилось or лишилось_екр or лишилось_дв or лишилось_назв:
        raise SystemExit(
            "чистка_каталогу: %s лишився БРУДНИМ після власної чистки — "
            "помилок слота %d, подвійних екранувань %d, мовних двійників %d, "
            "лежалих назв %d (було %d, %d, %d і %d). Це дефект даних або чистки, "
            "а не середовища."
            % (шлях, лишилось, лишилось_екр, лишилось_дв, лишилось_назв,
               помилок, екранувань, двійників, лежалих))
    _КЕШ_ЧИСТКИ[шлях_абс] = dict(шлях=шлях, помилок_до=помилок, екранувань_до=екранувань,
                                  двійників_до=двійників, лежалих_назв_до=лежалих,
                                  почищено=True, звіт=звіт)
    return _КЕШ_ЧИСТКИ[шлях_абс]


def почистити(вхід, вихід):
    д, к, ід_кат, не_одяг, помилки, компл, крій, без_роду = класифікувати(вхід)
    порядок = list(к.iter("offer"))
    індекс = {id(o): i for i, o in enumerate(порядок)}
    видалити = {індекс[id(o)] for o, _, _ in не_одяг}
    # Мовний двійник іде тим самим шляхом, що й «не одяг»: офер вирізається з
    # тексту цілком. Український запис того самого товару лишається на місці.
    двійники = мовні_двійники(к)
    видалити |= {індекс[id(o)] for o, _, _ in двійники}
    правки = {індекс[id(o)]: нов for o, _, _, нов in помилки}

    сирий = open(вхід, encoding="utf-8").read()
    # ЦІЛЬОВІ id КАТЕГОРІЙ — БЕЗПЕЧНО. `ід_кат` — мапа ТЕКСТ_КАТЕГОРІЇ→id, а
    # `нов` — ім'я СЛОТА. На старому каталозі вони випадково збігались; на
    # форматі жниварки v4.0, який `класифікувати` сама оголошує живим (рядки
    # 93-99), `ід_кат[нов]` кидав KeyError і гасив ліки, на які вказує
    # `build_артефакт.py:215`.
    ціль_id = {слот: ід_кат.get(слот) for слот in {н for _, _, _, н in помилки}}
    сирий, дописано_кат = _дописати_категорії(сирий, ціль_id)
    бракує = sorted(н for н in ціль_id if ціль_id[н] is None)
    if бракує:
        raise SystemExit(
            "чистка_каталогу: у файлі %s нема категорій для слотів %s і нема "
            "блоку <categories>, куди їх дописати. Без цільової категорії правка "
            "слота була б наполовину зробленою: param «слот» став би правильним, "
            "а категорія-лист і далі переважувала б його у feed.слот."
            % (вхід, ", ".join(бракує)))

    # ── ВІДНОВЛЕНА НАЗВА (рядок 182) ─────────────────────────────────────────
    # Оффери читаються тим самим `читати_yml`, що й усюди: будувати тут другий,
    # частковий розбір XML означало б завести другу правду про те, що таке
    # «колір» чи «параметри» речі. Порядок збігається з `порядок` і з
    # `_OFFER.finditer` — усі троє йдуть по `offer` згори вниз.
    # ВИПРАВЛЕНИЙ СЛОТ ПІДСТАВЛЯЄТЬСЯ ТУТ, а не лишається сирим: `назва_речі`
    # питає слот, коли дописує колір, і оффер, слот якого ця ж чистка щойно
    # виправила, мусить дістати назву за НОВИМ слотом.
    оферти = feed.читати_yml(вхід)[0]
    картки = назва_речі.читати_назви_карток()
    відновлені = {}
    for i, o in enumerate(оферти):
        if i in видалити:
            continue
        якщо_правка = правки.get(i)
        if якщо_правка:
            o = dict(o, параметри=dict(o.get("параметри") or {}, слот=якщо_правка))
        назва, джерело, причина = назва_речі.відновлена_назва(o, картки)
        if назва and назва != (o.get("назва") or ""):
            відновлені[i] = (назва, джерело, причина)

    шматки, кінець, n, екранувань = [], 0, 0, 0
    for i, м in enumerate(_OFFER.finditer(сирий)):
        шматки.append(сирий[кінець:м.start()])
        кінець = м.end()
        if i in видалити:
            n += 1
            continue
        текст, _екр = _розекранувати_сире(м.group(0))
        екранувань += _екр
        if i in правки:
            нов = правки[i]
            текст = re.sub(r"<categoryId>\d+</categoryId>",
                           "<categoryId>%s</categoryId>" % ціль_id[нов], текст, count=1)
            текст = re.sub(r'(<param name="слот">)[^<]*(</param>)',
                           r"\g<1>%s\g<2>" % нов, текст, count=1)
        текст = _вписати_назву(текст, *(відновлені.get(i) or (None, None, None)))
        шматки.append(текст)
    шматки.append(сирий[кінець:])
    вих = "".join(шматки)
    # Маркер — ОДИН на файл, одразу після відкриття <shop>: `_назви_лежалі`
    # шукає його в тексті, ET його не бачить, а `_розекранувати_сире` працює
    # всередині оферів і його не чіпає.
    вих = _МАРКЕР_НАЗВ.sub("", вих)
    маркер = "<!-- назва_показу: версія %d, речей %d -->" % (
        назва_речі.ВЕРСІЯ_ВІДНОВЛЕННЯ, len(відновлені))
    вих = re.sub(r"(<shop>)", r"\g<1>\n  " + маркер, вих, count=1)
    with open(вихід, "w", encoding="utf-8") as f:
        f.write(вих)
    return dict(видалено=n, двійників_знято=len(двійники), слотів_виправлено=len(правки),
                екранувань_виправлено=екранувань, назв_відновлено=len(відновлені),
                категорій_дописано=дописано_кат, байт=len(вих.encode("utf-8")))
