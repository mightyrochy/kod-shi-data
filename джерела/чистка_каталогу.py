# ── ЗАПИС: ТЕКСТОВА ХІРУРГІЯ, НЕ ПЕРЕСЕРІАЛІЗАЦІЯ ────────────────────────────
# ET.write() перепише ВЕСЬ файл: порядок атрибутів, самозакриття, екранування.
# Тоді diff у git — 10 МБ, і жодна правка не піддається огляду. Тому офери
# ріжуться й правляться на рівні тексту, а решта файла лишається байт у байт.
# ID НЕ УНІКАЛЬНИЙ (1 230 пар «ж-00237» у різних магазинах, пам'ять 28.08),
# тож офери адресуються ПОРЯДКОВИМ НОМЕРОМ, який збігається з ET.iter.
_OFFER = re.compile(r"<offer\b.*?</offer>", re.S)


def почистити(вхід, вихід):
    д, к, ід_кат, не_одяг, помилки, компл, крій, без_роду = класифікувати(вхід)
    порядок = list(к.iter("offer"))
    індекс = {id(o): i for i, o in enumerate(порядок)}
    видалити = {індекс[id(o)] for o, _, _ in не_одяг}
    правки = {індекс[id(o)]: нов for o, _, _, нов in помилки}

    сирий = open(вхід, encoding="utf-8").read()
    шматки, кінець, n = [], 0, 0
    for i, м in enumerate(_OFFER.finditer(сирий)):
        шматки.append(сирий[кінець:м.start()])
        кінець = м.end()
        if i in видалити:
            n += 1
            continue
        текст = м.group(0)
        if i in правки:
            нов = правки[i]
            текст = re.sub(r"<categoryId>\d+</categoryId>",
                           "<categoryId>%s</categoryId>" % ід_кат[нов], текст, count=1)
            текст = re.sub(r'(<param name="слот">)[^<]*(</param>)',
                           r"\g<1>%s\g<2>" % нов, текст, count=1)
        шматки.append(текст)
    шматки.append(сирий[кінець:])
    вих = "".join(шматки)
    # подвійне екранування жниварки: `&amp;quot;` доїжджає до картки як `&quot;`
    вих = вих.replace("&amp;quot;", "&quot;").replace("&amp;amp;", "&amp;")
    with open(вихід, "w", encoding="utf-8") as f:
        f.write(вих)
    return dict(видалено=n, слотів_виправлено=len(правки),
                байт=len(вих.encode("utf-8")))
