# ── МОВНИЙ ДВІЙНИК: ТОЙ САМИЙ ТОВАР ДВІЧІ ───────────────────────────────────
# Жниварка ходить і українською сторінкою товару, і його `/en/` (`/ru/`) версією,
# а `влиття_в_каталог` відсіває дублі за ТОЧНИМ url — і два записи одного товару
# лягають у каталог поруч. Наслідок бачив куратор на картці: рука 1 дала сукню
# «Ця ж сукня, залишається такою ніби я її придбала вчора» (ж-01466@vilni.store) —
# назва з блоку ВІДГУКІВ англомовної сторінки, ціни нема, а той самий товар у
# каталозі стоїть українською й з ціною («Сукня лляна Грінсборо», 2 950 ₴).
# ВИМІР на `каталог_повний` (12 405): 448 записів мають мовний сегмент
# у url, у 410 з них українська сторінка ТЕЖ у каталозі — kasandra 137, sezone 128,
# ricamare 63, vilni 55, alot 25, morandi 2. З них без ціни 118, з ціною 292.
# ДВА СВІДКИ, І ДРУГИЙ ОБОВ'ЯЗКОВИЙ: (1) url збігається до мовного сегмента —
# той самий магазин, той самий слаг; (2) щонайменше ОДИН файл фото спільний.
# Другий свідок перевірено на всіх 410 парах: спільне фото є в 410 із 410
# (`group_id` збігся лише в 131 — тому за ним самим судити не можна).
# ЩО ЛИШАЄТЬСЯ: український запис — він має назву мовою картки й ціну. Запис із
# мовним сегментом, чиєї української сторінки в каталозі НЕМА (38: morandi 32,
# ricamare 6), не чіпається — це не дубль, і його назву перекладає `назва_речі`.
_МОВНИЙ_СЕГМЕНТ = re.compile(r"^(https?://[^/]+)/(?:en|ru|rus|eng)/", re.I)
_РОЗМІР_ФАЙЛА = re.compile(r"-\d{2,4}x\d{2,4}(?=\.)")


def _файл_фото(url):
    """Ім'я файла знімка без розміру: крамниця віддає той самий кадр у кількох розмірах."""
    імя = str(url or "").split("?")[0].rstrip("/").split("/")[-1]
    return _РОЗМІР_ФАЙЛА.sub("", імя).lower()


def мовні_двійники(корінь):
    """Офери, які є ІНШОМОВНОЮ сторінкою товару, що вже стоїть у каталозі українською."""
    за_url = {}
    for o in корінь.iter("offer"):
        u = (o.findtext("url") or "").strip()
        if u and not _МОВНИЙ_СЕГМЕНТ.match(u):
            за_url.setdefault(u, o)
    двійники = []
    for o in корінь.iter("offer"):
        u = (o.findtext("url") or "").strip()
        if not u or not _МОВНИЙ_СЕГМЕНТ.match(u):
            continue
        укр = за_url.get(_МОВНИЙ_СЕГМЕНТ.sub(r"\1/", u))
        if укр is None:
            continue
        наші = {_файл_фото(p.text) for p in o.findall("picture") if p.text}
        їхні = {_файл_фото(p.text) for p in укр.findall("picture") if p.text}
        if наші & їхні:
            двійники.append((o, u, (укр.findtext("url") or "").strip()))
    return двійники


_ЛИШОК_ПІСЛЯ_МОВИ = re.compile(r"^/(?:ua|uk|en|ru|rus|eng)(?=/)", re.I)
_СЛУЖБОВИЙ_КАДР = 3


def _адреса_кадру(url):
    """Адреса знімка без розміру й хвоста (`?sc_content`): крамниця + шлях + файл."""
    р = urlsplit(str(url or "").strip())
    return _РОЗМІР_ФАЙЛА.sub("", р.netloc + р.path).lower().rstrip("/")


def _адреса_речі(url):
    """Канонічна адреса сторінки: без мовного префікса шляху й без хвоста запиту, крім вибору варіації.

    Запит `attribute_<таксономія>=<значення>` (його пише адаптер Woo, `жниварка.канонічна_з_запитом`) називає
    варіант товару: одна сторінка — кілька кольорів, і без нього всі вони мали б однаковий ключ. Значення
    лишається непрозорим рядком, код його не читає (п.12); решта запиту (`sc_content`, `route`) — хвіст.
    """
    р = urlsplit(str(url or "").strip())
    вибір = tuple(sorted((к.lower(), з.lower()) for к, з in parse_qsl(р.query) if к.lower().startswith("attribute_")))
    return р.netloc.lower(), _ЛИШОК_ПІСЛЯ_МОВИ.sub("", р.path).rstrip("/").lower(), вибір


# ОДИН ТОВАР — ОДНА РІЧ НА ЧИТАННІ КАТАЛОГУ. Ключ —
# крамниця + перший кадр (адреса без розміру й хвоста). Кадр, що стоїть на ≥ 3
# записах крамниці, службовий (банер, заглушка) і ключем не є: такі записи, як і
# записи без кадру, ключують канонічною адресою сторінки без мовного префікса, з
# вибором варіації Woo (`attribute_…`): колір — окрема річ.
# Назв код не порівнює (п.12). Лишається ПЕРШИЙ запис за порядком каталогу — його
# ж-номер; решта — двійники. Різні речі з однаковою назвою мають різні кадри й
# не зливаються.
def двійники_товару(корінь, пропущені=frozenset()):
    """[(двійник-офер, ключ, лишений-офер)] — повтори тієї самої речі в каталозі; `пропущені` (id офера) вже вирізано."""
    усі = [o for o in корінь.iter("offer") if id(o) not in пропущені]
    кадри = [_адреса_кадру(next((p.text for p in o.findall("picture") if p.text), "")) for o in усі]
    моделі = collections.defaultdict(set)
    for o, к in zip(усі, кадри):
        моделі[к].add((o.findtext("vendorCode") or "").strip() or _адреса_речі(o.findtext("url")))
    скільки = {к: len(м) for к, м in моделі.items()}
    лишені, двійники = {}, []
    for o, к in zip(усі, кадри):
        адр = _адреса_речі(o.findtext("url"))
        if к and скільки[к] < _СЛУЖБОВИЙ_КАДР:
            ключ = ("кадр", адр[0], к)
        elif адр[1]:
            ключ = ("адреса",) + адр
        else:
            continue
        перший = лишені.setdefault(ключ, o)
        if перший is not o:
            двійники.append((o, ключ, перший))
    return двійники


def всі_двійники(корінь, пропущені=frozenset()):
    """Мовні двійники й повтори товару: [(офер, лишений офер)], кожен офер раз.

    Службовий кадр судить лічба речей на ньому, тож вирізаний двійник міняє її: повтор шукається, доки
    є нові, — друга чистка вже почищеного каталогу не знаходить нічого (pitaya Marseille, 0 → 1)."""
    за_url = {}
    for o in корінь.iter("offer"):
        за_url.setdefault((o.findtext("url") or "").strip(), o)
    пари = {id(o): (o, за_url[укр]) for o, _, укр in мовні_двійники(корінь)}
    вирізані = set(пропущені) | set(пари)
    while True:
        нові = [(o, перший) for o, _, перший in двійники_товару(корінь, вирізані) if id(o) not in пари]
        if not нові:
            return list(пари.values())
        for o, перший in нові:
            пари.setdefault(id(o), (o, перший))
        вирізані |= {id(o) for o, _ in нові}


def таблиця_відповідності(пари):
    """{прибраний ж-номер: ж-номер, що лишився}: вердикти й «Замінити» не губляться."""
    куди = {o.get("id"): л.get("id") for o, л in пари}
    for ід in куди:
        л = куди[ід]
        for _ in range(len(куди)):
            if л not in куди:
                break
            л = куди[л]
        куди[ід] = л
    return куди


