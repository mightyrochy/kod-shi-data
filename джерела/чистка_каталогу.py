# ── ГЛИБИНА ЕКРАНУВАННЯ: ОДНЕ ЧИСЛО НА ВЕСЬ ФАЙЛ ─────────────────────────
# Два різні уявлення в одному модулі: `класифікувати` знімала сутності ДВІЧІ
# (html.unescape(html.unescape(...))), а запис — ОДИН раз. Тобто розпізнавач і
# писар вважали каталог екранованим на різну глибину, і ніде не було сказано, на
# яку саме. Число тут одне й уживається обома.
# ЧОМУ 2, А НЕ 1. Жниварка нормалізує ТЕКСТОВІ поля до нерухомої точки
# (`жниварка.py:229 розекранувати`, до трьох проходів), але URL фото крізь неї не
# йдуть (`жниварка.py:2400`: `picture` пишеться як є) — і саме там подвійне
# екранування живе: 307 `<picture>` несуть `&amp;amp;h=1200`. Один прохід знімає
# рівно те, що зміряно в цьому каталозі; другий — запас проти фіду, який екранує
# глибше, бо каталог сюди приходить і не від жниварки.
# ВИМІР на `каталог_повний.xml`: `&amp;quot;` — 24, `&amp;amp;` —
# 647, разом 671 місце; потрійного екранування (`&amp;amp;amp;`, `&amp;amp;quot;`)
# у цьому каталозі НЕМА — тобто другий прохід на ньому не міняє жодного байта.
ГЛИБИНА_ЕКРАНУВАННЯ = 2
# ── БУДЬ-ЯКА СУТНІСТЬ, А НЕ ДВІ НАЗВАНІ ───────────────────────────────────────
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. Зняття екранування лише двох сутностей —
# `&amp;quot;` і `&amp;amp;`, — а решту лишало в тексті крамниці буквально. На
# `каталог_повний.xml` (12 426 оферів) поза цими двома лежало ще 2 730 місць:
# `&amp;#8217;` — 1 119, `&amp;nbsp;` — 638, `&amp;#8211;` — 645, `&amp;#8220;`/
# `&amp;#8221;` — 170, `&amp;#40;`/`&amp;#41;` — 158, `&amp;mdash;` — 7,
# `&amp;rsquo;` — 6, `&amp;laquo;`/`&amp;raquo;` — 2. Після розбору ET вони
# ставали видимим текстом `&#8217;`, і `назва_речі.розкодувати` рятувала лише
# `назва_показу` — одне поле з багатьох: у розгорнутому «код не знає» картки
# стояло «В&#8217;язаний снуд з бавовни», бо заяву про річ
# складають із СИРИХ полів запису. Сутність знімається РАЗ, на вході
# каталогу, і чистим стає весь текст крамниці — назва, опис і кожен param, —
# хай його читає картка, заява суду, промпт моделі чи звіт власника.
# ЧОМУ НЕ СЛОВНИК СУТНОСТЕЙ: `html.unescape` знає їх усі; невідому сутність
# воно віддає незміненою, і тоді ми теж не чіпаємо її (див. `_зняти_шар`).
# П'ЯТЬ СЛУЖБОВИХ XML-СИМВОЛІВ ЛИШАЮТЬСЯ ЕКРАНОВАНИМИ на один шар: файл після
# чистки має лишитись XML, а `&` чи `"` літерою всередині атрибута його ламає.
# Саме це й робили обидві старі пари (`&amp;quot;` → `&quot;`, `&amp;amp;` →
# `&amp;`), тож на них поведінка не міняється ні на байт.
_СУТНІСТЬ = re.compile(r"&amp;(#\d{1,7}|#[xX][0-9a-fA-F]{1,6}|[a-zA-Z][a-zA-Z0-9]{1,31});")
_XML_СЛУЖБОВІ = {"&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;"}


def _зняти_шар(м):
    """`&amp;#8217;` → `’`, `&amp;amp;` → `&amp;`, невідома сутність — як була."""
    сутність = "&" + м.group(1) + ";"
    символ = html.unescape(сутність)
    if len(символ) != 1 or символ == сутність:
        return м.group(0)
    return _XML_СЛУЖБОВІ.get(символ, символ)


def _розекранувати(текст):
    """Текст, уже розібраний ET (один шар сутностей знято), — ще ГЛИБИНА разів."""
    for _ in range(ГЛИБИНА_ЕКРАНУВАННЯ):
        текст = html.unescape(текст)
    return текст


def _розекранувати_сире(текст):
    """Те саме на рівні СИРОГО XML, без пересеріалізації.

    Повертає (текст, скільки ЗАМІН зроблено) — не «місць»: одне місце, екрановане
    на всю ГЛИБИНУ, дає стільки замін, скільки шарів з нього знято. Лічба потрібна,
    бо екранування оголошене окремим класом правок і йде у відповідь `почистити`
    своїм полем."""
    місць = 0
    for _ in range(ГЛИБИНА_ЕКРАНУВАННЯ):
        текст, знято = _СУТНІСТЬ.subn(_зняти_шар, текст)
        місць += знято
    return текст, місць


# ── АРТИКУЛ КРАМНИЦІ З НАЗВИ ─────────────────────────────────────────────────
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. Показ давно чистить назву сам (`назва_речі.почистити`),
# і на картці стоїть `назва_показу`. Але СИРЕ поле `<name>` читають і інші:
# заяву «код не знає» складають із сирих полів запису, звіт власника
# друкує їх усі, `пакет_моделі` шукає бажання жінки по тексту речі. Тому на
# картках траплялись голі артикули — «Лофери V шкіряні
# зелені 000399639». Це та сама причина, через яку зняття HTML-сутностей
# Чистим має бути ТЕКСТ КАТАЛОГУ, а не одне поле показу.
# ЧОМУ ПІСЛЯ ЗНЯТТЯ СУТНОСТЕЙ, А НЕ ДО: правило працює на СИРОМУ тексті офера
# (`&amp;` тут уже став `&`), і цифри сутності `&#65533;` для нього — не код
# лише завдяки поглядам `&#` і `;` у `назва_речі._ТОКЕН_КОДУ`. Знімати артикул
# до сутностей означало б покладатись на ці погляди двічі.
# ЧОМУ ВУЖЧЕ ПРАВИЛО, А НЕ `назва_речі.почистити`: почистити знімає ще рекламу,
# розмір і код кольору крамниці, зводить регістр і часом міняє назву цілком —
# у каталозі це були б ВТРАЧЕНІ дані (розмір і колір там поле речі),
# а не косметика. Тут іде тільки те, що не є нічим,
# крім артикула: `назва_речі.зняти_артикул` з власним виміром.
# ПОКАЗ ЛИШАЄТЬСЯ БАЙТ У БАЙТ. `назва_показу` рахується ДО цієї правки, з назви
# фіду, і `зняти_код` вужчого правила не кличе — навмисно. Правила `_КОДИ`
# прикріплені до кінця назви й тримаються ЗА ЦИФРИ артикула: welfare «Рюкзак
# жіночий Welfare 32130 WHITE/BLK» дочищається до «Рюкзак жіночий Welfare» саме
# тому, що перед кодом кольору стоїть число. Знявши артикул раніше, ми забрали б
# у показу цей якір і лишили б жінці «Welfare WHITE/BLK» — вимір: 76 назв. Тож
# порядок тут один: спершу порахувати назву показу, тоді чистити сиру.
# ВИМІР — у пробі `проби/артикул_у_назві.py` (числа до/після на каталозі).
_ІМ_НАЗВИ = re.compile(r"(<name>)([^<]*)(</name>)")


def _правка_назви(текст_офера, правило, ре=_ІМ_НАЗВИ):
    """(текст офера, 1 якщо текст вкоротило) — `правило` над вмістом `<name>`.

    Працює на сирому тексті, а не на розібраному дереві: п'ять службових
    XML-символів лишаються екранованими, бо правила вирізають ЛИШЕ токени з
    `[0-9A-Za-z-/]`, і жодного символу назви не переписують.
    `ре` — яке саме поле правиться: типово `<name>`, а також
    `param категорія_магазину` (`_ІМ_РОЗДІЛУ`). Обидва — ТЕКСТ КРАМНИЦІ в тому
    самому записі, і чистити їх двома різними шляхами означало б завести дві
    правди про те, що таке код моделі."""
    м = ре.search(текст_офера)
    if not м:
        return текст_офера, 0
    нова = правило(м.group(2))
    if нова == м.group(2):
        return текст_офера, 0
    return (текст_офера[:м.start(2)] + нова + текст_офера[м.end(2):]), 1


def _зняти_артикул_у_назві(текст_офера):
    """Артикул крамниці з `<name>` — див. блок вище."""
    return _правка_назви(текст_офера, назва_речі.зняти_артикул)


# ── САМОТНЯ ЛІТЕРА МОДЕЛІ — ПОРУЧ З АРТИКУЛОМ І ПІСЛЯ НЬОГО ─────────────────
# ПОРЯДОК ЗНАЧУЩИЙ, і це не косметика. Літера знімається лише там, де за нею йде
# українське слово або кінець назви, — а поки артикул на місці, за літерою стоїть
# ЧИСЛО: «Чоботи Козаки жіночі F 000123». Тому артикул іде першим, і лише тоді
# літера стає останнім токеном і правило її бачить. Обернений порядок лишив би
# частину літер у назві, і другий прогін чистки давав би інший результат, ніж
# перший (та сама вимога нерухомої точки, що й у `зняти_артикул`).
def _зняти_літеру_у_назві(текст_офера):
    """Самотню літеру моделі з `<name>` — `назва_речі.зняти_літеру_моделі`."""
    return _правка_назви(текст_офера, назва_речі.зняти_літеру_моделі)


# ── КОД МОДЕЛІ КРАМНИЦІ — ТРЕТІМ, ПІСЛЯ ЛІТЕРИ ──────────────────────────────
# Порядок той самий і з тієї самої причини, що в `назва_речі.почистити`: токен
# зветься кодом лише на позиції коду (після українського слова й перед
# українським словом або в кінці), а доки артикул на місці, за ним стоїть число.
# ЧОМУ АРГУМЕНТОМ, А НЕ ВСЕРЕДИНІ ПРАВИЛА: набір кодів — ознака КРАМНИЦІ, і
# зміряти її можна лише на всьому її асортименті. Один офер про свою крамницю
# нічого не знає, тому набір приходить згори, з `почистити`.
def _зняти_код_моделі_у_назві(текст_офера, коди):
    """Дво- й трилітерний код моделі з `<name>` — `назва_речі.зняти_код_моделі`."""
    if not коди:
        return текст_офера, 0
    return _правка_назви(текст_офера, lambda н: назва_речі.зняти_код_моделі(н, коди))


# ── ТОЙ САМИЙ КОД У РОЗДІЛІ КРАМНИЦІ ─────────────────────────────────────────
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. Дво- й трилітерний код моделі знято з НАЗВИ, і на
# картці giardini стало «Мокасини замшеві джинсові». Але той самий рядок крамниця
# пише вдруге — шляхом свого розділу: «Головна > Колекція > Для нього > Мокасини >
# Мокасини PS замшеві джинсові». Поле стоїть у `каталог_розбір.ЗАВЖДИ`, тобто
# їде МОДЕЛІ як слова крамниці (`поля_крамниці` → `params` промпту розбору), і
# доїжджає в заяву «код не знає» та у звіт власника. Отже код, прибраний із
# картки, і далі в промпті: модель читає «Мокасини PS» і має вирішити, що таке PS.
# ВИМІР на `каталог_повний.xml.gz` (11 993 офери, проба `проби/поля_каталогу.py`):
# 156 розділів giardini несуть код, уже знятий із назви тієї самої речі.
# ОЗНАКА — ТА САМА, І ЦЕ ВСЯ СУТЬ. Судиться КРАМНИЦЯ (`коди_крамниць`), не форма
# токена: по каталогу токен «дві-три великі латинські літери на позиції коду»
# стоїть у 341 полі 12 крамниць, і майже всюди він щось означає — «EVA» (піна
# устілки, kasandra 201), «YKK» (застібка, vmma 32), «XL»/«XS»/«OS» (розмір),
# «ONE» (колір cooshwear). Правило за формою зіпсувало б їх усі. Крамниця з
# кодами на цьому каталозі одна — giardini; cultboutique «Мюлі жіночі DOR»
# лишається недоторканою рівно так само, як лишилась її НАЗВА.
ПАРАМ_РОЗДІЛУ = "категорія_магазину"
_ІМ_РОЗДІЛУ = re.compile(r'(<param name="%s">)([^<]*)(</param>)' % ПАРАМ_РОЗДІЛУ)


def _зняти_код_моделі_у_розділі(текст_офера, коди):
    """Код моделі з `param категорія_магазину` — тим самим правилом, що з назви."""
    if not коди:
        return текст_офера, 0
    return _правка_назви(текст_офера, lambda н: назва_речі.зняти_код_моделі(н, коди),
                         _ІМ_РОЗДІЛУ)


# ── ПЛИТКА «СХОЖІ ТОВАРИ» У PARAM ────────────────────────────────────────────
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. Жниварка читає з картки пари «ключ — значення» з li/tr/dl,
# а плитка блоку «схожі товари» теж лежить у li: bella-bicchi у полі `~Ціна` й
# `~Швидкий перегляд Ціна` має ЧУЖУ плитку — «від 4 950 грн Ошатна літня жіноча
# сукня оверсайз… Bella Bicchi 0 0 В наявності Арт. 2319 Код 27559», на жіночій
# сумці — «770 грн Жіноча шапка 0 0 В наявності Арт. zh_shap1 …». Поля їдуть
# МОДЕЛІ як слова крамниці (`каталог_розбір.поля_крамниці`) і складаються в `повний`
# текст `фід_верхнє` — тобто розбір речі читає назву й ціну ІНШОЇ речі.
# ОЗНАКА ПЛИТКИ — ЇЇ ВЛАСНИЙ ХВІСТ, не форма ключа: «<ціле> <ціле> <статус> Арт.»
# («0 0 В наявності Арт. …» — лічильники й наявність, яких на картці речі не буває).
# Ключ не судиться: власна ціна речі лежить у `<price>`, і param `~Ціна` без плитки
# (чисте «770 грн») лишається, якби такий трапився.
# ВИМІР на `каталог_повний.xml.gz` (12 426 оферів, проба `проби/fid2a_1988.py`): плитку
# несуть 190 оферів bella-bicchi, у них 377 param (`~Ціна` 190, `~Швидкий перегляд Ціна`
# 187); в інших крамницях — нуль.
_ПЛИТКА_СХОЖОГО = re.compile(r"\b\d+ \d+ (?:[^\W\d_]+ ){1,4}Арт\. ")
_ПАРАМ_ЦІЛИМ = re.compile(r'<param name="[^"]*">[^<]*</param>')


def _зняти_плитку_схожих(текст_офера):
    """(текст офера, скільки param знято) — param, чиє значення є плиткою «схожих товарів»."""
    знято = 0

    def _рішення(м):
        nonlocal знято
        if _ПЛИТКА_СХОЖОГО.search(м.group(0)):
            знято += 1
            return ""
        return м.group(0)
    return _ПАРАМ_ЦІЛИМ.sub(_рішення, текст_офера), знято


# ── ТОЙ САМИЙ КОД У ГОЛОВІ ОПИСУ ─────────────────────────────────────────────
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. Код моделі знято з НАЗВИ й РОЗДІЛУ
# крамниці. Третє місце, де той самий рядок стоїть цілим, — голова `param опис`:
# giardini починає опис фразою, що повторює назву речі («Черевики Жокейки Жіночі
# LB Характеристики Виробник Португалія…», ж-09361). Поле їде МОДЕЛІ як слова
# крамниці й доїжджає в заяву «код не знає» та у звіт власника, тож модель і далі
# читає «Черевики LB» і має вирішити, що таке LB.
#
# ЧОМУ ЛИШЕ ГОЛОВА, А НЕ ВЕСЬ ОПИС, І ЦЕ НЕ ОСТОРОЖНІСТЬ, А ВИМІР. Опис — ПРОЗА,
# і той самий токен у ній щось означає: у тих самих трьох речах стоїть «Матеріал
# підошви EVA» — піна устілки, не код. Вимір на `каталог_повний.xml.gz` (10 178
# описів): без межі голови правило чіпає 59 описів, з них 19 — токен ГЛУБОКО в
# прозі (позиція 45, 63, 84, 99), і 17 описів коротшають більш ніж на один токен,
# тобто правило починає різати речення. З межею — 57 описів, УСІ giardini, кожен
# РІВНО на один токен, позиція токена завжди < 8. Межа 8 не підігнана: 6, 8 і 12
# дають те саме число, бо голова, що повторює назву, коротка за побудовою.
#
# ДРУГА УМОВА, І ВОНА Й РОЗРІЗНЯЄ КОД ВІД СЛОВА: токен знімається лише той, що
# стоїть У НАЗВІ ЦІЄЇ САМОЇ РЕЧІ. «EVA» у назві не стоїть ніде; «LB», «EL», «QA»
# стоять. Тобто свідок — не форма токена й навіть не набір крамниці сам собою, а
# збіг «те, що ми щойно зняли з назви, повторилось у голові опису».
ПАРАМ_ОПИСУ = "опис"
_ІМ_ОПИСУ = re.compile(r'(<param name="%s">)([^<]*)(</param>)' % ПАРАМ_ОПИСУ)
ГОЛОВА_ОПИСУ = 8
_ЛАТИНСЬКЕ_СЛОВО = re.compile(r"[A-Za-z]+")


def _зняти_код_моделі_в_описі(текст_офера, коди):
    """Код моделі з ГОЛОВИ `param опис` — лише токени, що стоять у `<name>` цієї речі.

    Кличеться ДО правки `<name>`: набір беремо з назви, поки код у ній ще є.
    Пробіли лишаються байт у байт — токен знімається разом із пробілом ПЕРЕД ним,
    а не через розбір і склеювання опису заново."""
    if not коди:
        return текст_офера, 0
    м = _ІМ_НАЗВИ.search(текст_офера)
    у_назві = (set(_ЛАТИНСЬКЕ_СЛОВО.findall(м.group(2))) & set(коди)) if м else set()
    if not у_назві:
        return текст_офера, 0

    def правило(опис):
        шматки, вихід, слів, знято = re.split(r"(\s+)", опис), [], 0, False
        for i, ш in enumerate(шматки):
            if i % 2 == 0 and ш:
                слів += 1
                if слів <= ГОЛОВА_ОПИСУ and ш in у_назві:
                    if вихід and not вихід[-1].strip():
                        вихід.pop()
                    знято = True
                    continue
            вихід.append(ш)
        return "".join(вихід) if знято else опис

    return _правка_назви(текст_офера, правило, _ІМ_ОПИСУ)


def _крамниця(offer):
    """Ім'я крамниці офера: `param магазин`, а без нього — хвіст id («ж-08905@giardini»).

    Обидва шляхи живі: `param магазин` пише жниварка v4.0, а старий каталог його
    не має зовсім, і тоді крамницю несе лише id."""
    п = offer.get("параметри") or {}
    return (п.get("магазин") or str(offer.get("id") or "").rsplit("@", 1)[-1]).strip().lower()


def коди_крамниць(оферти, пропустити=()):
    """{крамниця: frozenset токенів-кодів} — рішення про кожну крамницю каталогу.

    Один прохід на каталог: `назва_речі.коди_моделі` судить крамницю за тим,
    скільком РОДАМ речей належить той самий токен (див. блок у `назва_речі`).
    Розділи крамниці йдуть туди ДРУГИМ аргументом: судити ними не можна (рід
    речі читається з назви), а доповнити набір уже засудженої крамниці — можна,
    інакше «Човники MC лакові білі» лишився б із кодом у промпті моделі."""
    назви = collections.defaultdict(list)
    розділи = collections.defaultdict(list)
    for i, o in enumerate(оферти):
        if i in пропустити:
            continue
        кр = _крамниця(o)
        назви[кр].append(назва_речі.почистити(str(o.get("назва") or "")))
        розділи[кр].append(str((o.get("параметри") or {}).get(ПАРАМ_РОЗДІЛУ) or ""))
    return {кр: назва_речі.коди_моделі(нн, розділи[кр]) for кр, нн in назви.items()}


def кольори_крамниць(оферти, пропустити=()):
    """{крамниця: frozenset токенів-кодів кольору} — рішення про кожну крамницю.

    СИРІ назви, а не почищені, і це вся різниця з `коди_крамниць`: свідок кодy
    кольору — артикул, що стоїть ПЕРЕД ним, а `почистити` артикул уже зняла.
    Рішення так само ухвалюється раз, на всьому асортименті крамниці."""
    назви = collections.defaultdict(list)
    for i, o in enumerate(оферти):
        if i in пропустити:
            continue
        назви[_крамниця(o)].append(назва_речі.розкодувати(str(o.get("назва") or "")))
    return {кр: назва_речі.коди_кольору(нн) for кр, нн in назви.items()}


