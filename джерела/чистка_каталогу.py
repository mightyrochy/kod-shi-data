# -*- coding: utf-8 -*-
"""Чистка каталогу: три дефекти ДАНИХ, кожен зі своїм наслідком у реальному образі.

1. НЕ ОДЯГ. Валізи, гаманці, парасолі, чохли. `feed.слот` уже віддає їм None,
   тож у пул вони не потрапляють — але лежать у файлі, важать байти й псують
   кожне число «речей у каталозі», на яке хтось спирається.

2. ПОДВІЙНЕ ЕКРАНУВАННЯ. `&amp;quot;` у назві доїжджає до картки тестувальниці
   як «Штани &quot;Зозулька&quot;». Це той дефект, який людина бачить очима, і
   він коштує довіри до всієї картки.

3. ПОМИЛКА СЛОТА. Оголошений слот (категорія-ім'я + param «слот») переважує
   назву за побудовою `feed.слот`, і це правильно, доки оголошення істинне.
   Де воно хибне, річ входить у ЧУЖИЙ пул: «Жакет з бахромою» лежить у слоті
   «сумка» і може стати сумкою образу.

ЧОГО ТУТ НЕМА НАВМИСНО:
   · 2 582 речі без слова кольору НЕ видаляються. Усі 2 582 мають фото, а
     кеш кольорів має 402 записи й НУЛЬ вимірів: це речі НЕВИМІРЯНІ, а не
     непридатні. Видалити їх — назавжди закрити третину каталогу.
   · Комплекти («костюм зі штанами і кардиганом») не чіпаються: у них немає
     правильного слота, бо це дві речі в одному SKU. Це рішення власника.
"""
import re, sys, html, collections
import xml.etree.ElementTree as ET
import feed
from аудит_слотів import РОДИНА, _прикметник

КОМПЛЕКТ = ("костюм-двійк", "костюм-трійк", "комплект", " набір", "набір ",
            "двійка", "трійка", "костюм з", "костюм зі", "костюм вільного")
# «плаття» (укр.) не ловиться ключем «плать» — м'який знак. Латентна прогалина
# feed.СЛОТ_КЛЮЧІ: на ЦЬОМУ каталозі нічого не міняє (усі 26 речей мають
# оголошений слот «сукня»), але аудит без неї звинувачує магазин у своїй сліпоті.
ДОКЛЮЧІ = {"сукня": ("платт",)}

# ── ГЛИБИНА ЕКРАНУВАННЯ: ОДНЕ ЧИСЛО НА ВЕСЬ ФАЙЛ (10.09.2026) ────────────────
# Було два різні уявлення в одному модулі: `класифікувати` знімала сутності ДВІЧІ
# (html.unescape(html.unescape(...))), а запис — ОДИН раз. Тобто розпізнавач і
# писар вважали каталог екранованим на різну глибину, і ніде не було сказано, на
# яку саме. Число тут одне й уживається обома.
# ЧОМУ 2, А НЕ 1. Жниварка нормалізує ТЕКСТОВІ поля до нерухомої точки
# (`жниварка.py:229 розекранувати`, до трьох проходів), але URL фото крізь неї не
# йдуть (`жниварка.py:2400`: `picture` пишеться як є) — і саме там подвійне
# екранування живе: 307 `<picture>` несуть `&amp;amp;h=1200`. Один прохід знімає
# рівно те, що зміряно в цьому каталозі; другий — запас проти фіду, який екранує
# глибше, бо каталог сюди приходить і не від жниварки.
# ВИМІР на `каталог_повний.xml` (10.09.2026): `&amp;quot;` — 24, `&amp;amp;` —
# 647, разом 671 місце; потрійного екранування (`&amp;amp;amp;`, `&amp;amp;quot;`)
# у цьому каталозі НЕМА — тобто другий прохід на ньому не міняє жодного байта.
ГЛИБИНА_ЕКРАНУВАННЯ = 2
# Пари для СИРОГО XML: після розбору ET `&quot;` стане `"`, а `&amp;` — `&`.
_ЕКРАНОВАНІ = (("&amp;quot;", "&quot;"), ("&amp;amp;", "&amp;"))


def _розекранувати(текст):
    """Текст, уже розібраний ET (один шар сутностей знято), — ще ГЛИБИНА разів."""
    for _ in range(ГЛИБИНА_ЕКРАНУВАННЯ):
        текст = html.unescape(текст)
    return текст


def _розекранувати_сире(текст):
    """Те саме на рівні СИРОГО XML, без пересеріалізації.

    Повертає (текст, скільки ЗАМІН зроблено) — не «місць»: одне місце, екрановане
    на всю ГЛИБИНУ, дає стільки замін, скільки шарів з нього знято. Лічба потрібна,
    бо екранування оголошене окремим класом правок і йде у відповідь `почистити`
    своїм полем."""
    місць = 0
    for _ in range(ГЛИБИНА_ЕКРАНУВАННЯ):
        for з, на in _ЕКРАНОВАНІ:
            місць += текст.count(з)
            текст = текст.replace(з, на)
    return текст, місць


def _ключі(слот):
    родина = [s for s, _ in feed.СЛОТ_КЛЮЧІ
              if РОДИНА.get(s, s) == РОДИНА.get(слот, слот)]
    out = []
    for с, кл in feed.СЛОТ_КЛЮЧІ:
        if с in родина:
            out.extend(кл)
    out.extend(ДОКЛЮЧІ.get(РОДИНА.get(слот, слот), ()))
    return out


def _іменник(назва, ключі):
    """Найраніший ключ-ІМЕННИК у назві → (позиція, ключ) або None."""
    кращ = None
    for k in ключі:
        п = назва.find(k)
        if п < 0 or _прикметник(назва, п, k):
            continue
        пастки = feed.ПАСТКИ_ПІДРЯДКА.get(k)
        if пастки and any(x in назва for x in пастки):
            continue
        if кращ is None or п < кращ[0]:
            кращ = (п, k)
    return кращ


def тип_назви(назва):
    кращ = None
    for сл, кл in feed.СЛОТ_КЛЮЧІ:
        r = _іменник(назва, list(кл) + list(ДОКЛЮЧІ.get(сл, ())))
        if r and (кращ is None or r[0] < кращ[0]):
            кращ = (r[0], сл, r[1])
    return кращ


def розібрати(шлях):
    дерево = ET.parse(шлях)
    корінь = дерево.getroot()
    кат = {c.get("id"): (c.text or "").strip() for c in корінь.iter("category")}
    ід_кат = {v: k for k, v in кат.items()}
    return дерево, корінь, кат, ід_кат


def класифікувати(шлях):
    дерево, корінь, кат, ід_кат = розібрати(шлях)
    не_одяг, помилки, комплекти, крій, без_роду = [], [], [], [], []
    for o in корінь.iter("offer"):
        назва_сира = (o.findtext("name") or o.findtext("n") or "")
        назва = _розекранувати(назва_сира).lower()
        оголош = кат.get(o.findtext("categoryId"), "")
        if any(x in назва for x in feed.НЕ_ОДЯГ):
            не_одяг.append((o, назва_сира, оголош)); continue
        r = тип_назви(назва)
        if r is None:
            continue
        _, зн, k = r
        # ── ДВА ФОРМАТИ КАТЕГОРІЇ, ОБИДВА ЖИВІ (07.09.2026) ──────────────────
        # (1) старий каталог: категорія — саме ім'я слота («верх», «низ»);
        # (2) жниварка v4.0: категорія магазину дослівно («Жіночі сумки через
        #     плече»), і рід речі в ній треба ЗНАЙТИ тим самим розпізнавачем,
        #     що й у назві. Порядок важить: `тип_назви("верх")` — None, бо
        #     «верх» не іменник речі; якби цей шлях стояв перший, 3 226 речей
        #     старого каталогу стали б «без роду».
        _ог = (оголош or "").strip().lower()
        if feed._АРТИКУЛ_ЯК_КАТЕГОРІЯ.match(_ог):
            # Категорія-артикул («Шарф-35100») — назва одного товару, не клас.
            # `feed.слот` її вже глушить; тут той самий рядок, інакше чистка
            # звітувала б як «помилку слота» те, чого в слоті вже нема, і
            # `build_артефакт` відмовляв би збирати на порожньому місці.
            без_роду.append((o, назва_сира, оголош, зн)); continue
        if РОДИНА.get(зн, зн) == РОДИНА.get(_ог, _ог):
            continue
        _рк = тип_назви(_ог)
        if _рк is not None:
            if РОДИНА.get(зн, зн) == РОДИНА.get(_рк[1], _рк[1]):
                continue
        elif not any(_ог == с or РОДИНА.get(с, с) == _ог for с, _ in feed.СЛОТ_КЛЮЧІ):
            # Категорія не називає роду речі й не є іменем слота («ОСІНЬ-ЗИМА»,
            # «Розпродаж», «Топ продажів»). Це не твердження про слот — отже, не
            # може бути хибним твердженням. Рахується окремо, а не мовчки.
            без_роду.append((o, назва_сира, оголош, зн)); continue
        # СКЛАДЕНИЙ КРІЙ — ЗА ВИВЕДЕНИМ РОДОМ КАТЕГОРІЇ, НЕ ЗА ЇЇ ТЕКСТОМ.
        # `_ключі` бере родину слота; на старому каталозі категорія БУЛА слотом
        # («верх»), і 108 речей «сукня-сорочка» законно йшли сюди. На фразі
        # «Жіночі жакети і піджаки» `_ключі` віддавав порожньо, і бомбер у
        # категорії піджаків ставав «помилкою слота» замість складеного крою.
        if _іменник(назва, _ключі(_рк[1] if _рк else оголош)):
            крій.append((o, назва_сира, оголош, зн)); continue
        if any(x in назва for x in КОМПЛЕКТ):
            комплекти.append((o, назва_сира, оголош, зн)); continue
        помилки.append((o, назва_сира, оголош, зн))
    # `без_роду` — восьмим, щоб індекси наявних викликачів (build_артефакт бере [4])
    # лишились ті самі.
    return дерево, корінь, ід_кат, не_одяг, помилки, комплекти, крій, без_роду


