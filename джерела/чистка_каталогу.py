# ── БУДЬ-ЯКА СУТНІСТЬ, А НЕ ДВІ НАЗВАНІ (Л-11, 27.09.2026, знахідка Т-4 №3) ───
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. Доти зняття екранування знало рівно дві сутності —
# `&amp;quot;` і `&amp;amp;`, — а решту лишало в тексті крамниці буквально. На
# `каталог_повний.xml` (12 426 оферів) поза цими двома лежало ще 2 730 місць:
# `&amp;#8217;` — 1 119, `&amp;nbsp;` — 638, `&amp;#8211;` — 645, `&amp;#8220;`/
# `&amp;#8221;` — 170, `&amp;#40;`/`&amp;#41;` — 158, `&amp;mdash;` — 7,
# `&amp;rsquo;` — 6, `&amp;laquo;`/`&amp;raquo;` — 2. Після розбору ET вони
# ставали видимим текстом `&#8217;`, і `назва_речі.розкодувати` рятувала лише
# `назва_показу` — одне поле з багатьох: у розгорнутому «код не знає» картки
# стояло «В&#8217;язаний снуд з бавовни» (Т-4, знахідка 3), бо заяву про річ
# складають із СИРИХ полів запису. Тепер сутність знімається РАЗ, на вході
# каталогу, і чистим стає весь текст крамниці — назва, опис і кожен param, —
# хай його читає картка, заява суду, промпт моделі чи звіт власника.
# ЧОМУ НЕ СЛОВНИК СУТНОСТЕЙ: `html.unescape` знає їх усі; невідому сутність
# воно віддає незміненою, і тоді ми теж не чіпаємо її (див. `_зняти_шар`).
# П'ЯТЬ СЛУЖБОВИХ XML-СИМВОЛІВ ЛИШАЮТЬСЯ ЕКРАНОВАНИМИ на один шар: файл після
# чистки має лишитись XML, а `&` чи `"` літерою всередині атрибута його ламає.
# Саме це й робили обидві старі пари (`&amp;quot;` → `&quot;`, `&amp;amp;` →
# `&amp;`), тож на них поведінка не міняється ні на байт.
_СУТНІСТЬ = re.compile(r"&amp;(#\d{1,7}|#[xX][0-9a-fA-F]{1,6}|[a-zA-Z][a-zA-Z0-9]{1,31});")
_XML_СЛУЖБОВІ = {"&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;"}


def _зняти_шар(м):
    """`&amp;#8217;` → `’`, `&amp;amp;` → `&amp;`, невідома сутність — як була."""
    сутність = "&" + м.group(1) + ";"
    символ = html.unescape(сутність)
    if len(символ) != 1 or символ == сутність:
        return м.group(0)
    return _XML_СЛУЖБОВІ.get(символ, символ)


def _розекранувати(текст):
    """Текст, уже розібраний ET (один шар сутностей знято), — ще ГЛИБИНА разів."""
    for _ in range(ГЛИБИНА_ЕКРАНУВАННЯ):
        текст = html.unescape(текст)
    return текст


def _розекранувати_сире(текст):
    """Те саме на рівні СИРОГО XML, без пересеріалізації.

    Повертає (текст, скільки ЗАМІН зроблено) — не «місць»: одне місце, екрановане
    на всю ГЛИБИНУ, дає стільки замін, скільки шарів з нього знято. Лічба потрібна,
    бо екранування оголошене окремим класом правок і йде у відповідь `почистити`
    своїм полем."""
    місць = 0
    for _ in range(ГЛИБИНА_ЕКРАНУВАННЯ):
        текст, знято = _СУТНІСТЬ.subn(_зняти_шар, текст)
        місць += знято
    return текст, місць


# ── АРТИКУЛ КРАМНИЦІ З НАЗВИ (Л-12, 27.09.2026, ручні проходи Т-3/Т-4) ───────
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. Показ давно чистить назву сам (`назва_речі.почистити`),
# і на картці стоїть `назва_показу`. Але СИРЕ поле `<name>` читають і інші:
# заяву «код не знає» складають із сирих полів запису (#380), звіт власника
# друкує їх усі, `пакет_моделі` шукає бажання жінки по тексту речі. Тому на
# картках ручних проходів 27.09 траплялись голі артикули — «Лофери V шкіряні
# зелені 000399639». Це та сама причина, через яку зняття HTML-сутностей
# переїхало сюди (#400): чистим має бути ТЕКСТ КАТАЛОГУ, а не одне поле показу.
# ЧОМУ ПІСЛЯ ЗНЯТТЯ СУТНОСТЕЙ, А НЕ ДО: правило працює на СИРОМУ тексті офера
# (`&amp;` тут уже став `&`), і цифри сутності `&#65533;` для нього — не код
# лише завдяки поглядам `&#` і `;` у `назва_речі._ТОКЕН_КОДУ`. Знімати артикул
# до сутностей означало б покладатись на ці погляди двічі.
# ЧОМУ ВУЖЧЕ ПРАВИЛО, А НЕ `назва_речі.почистити`: почистити знімає ще рекламу,
# розмір і код кольору крамниці, зводить регістр і часом міняє назву цілком —
# у каталозі це були б ВТРАЧЕНІ дані (розмір і колір там поле речі, і власник
# 27.09 сказав їх не чіпати), а не косметика. Тут іде тільки те, що не є нічим,
# крім артикула: `назва_речі.зняти_артикул` з власним виміром.
# ПОКАЗ ЛИШАЄТЬСЯ БАЙТ У БАЙТ. `назва_показу` рахується ДО цієї правки, з назви
# фіду, і `зняти_код` вужчого правила не кличе — навмисно. Правила `_КОДИ`
# прикріплені до кінця назви й тримаються ЗА ЦИФРИ артикула: welfare «Рюкзак
# жіночий Welfare 32130 WHITE/BLK» дочищається до «Рюкзак жіночий Welfare» саме
# тому, що перед кодом кольору стоїть число. Знявши артикул раніше, ми забрали б
# у показу цей якір і лишили б жінці «Welfare WHITE/BLK» — вимір: 76 назв. Тож
# порядок тут один: спершу порахувати назву показу, тоді чистити сиру.
# ВИМІР — у пробі `проби/артикул_у_назві.py` (числа до/після на каталозі).
_ІМ_НАЗВИ = re.compile(r"(<name>)([^<]*)(</name>)")


def _правка_назви(текст_офера, правило, ре=_ІМ_НАЗВИ):
    """(текст офера, 1 якщо текст вкоротило) — `правило` над вмістом `<name>`.

    Працює на сирому тексті, а не на розібраному дереві: п'ять службових
    XML-символів лишаються екранованими, бо правила вирізають ЛИШЕ токени з
    `[0-9A-Za-z-/]`, і жодного символу назви не переписують.
    `ре` — яке саме поле правиться: типово `<name>`, а рядком 183 ще й
    `param категорія_магазину` (`_ІМ_РОЗДІЛУ`). Обидва — ТЕКСТ КРАМНИЦІ в тому
    самому записі, і чистити їх двома різними шляхами означало б завести дві
    правди про те, що таке код моделі."""
    м = ре.search(текст_офера)
    if not м:
        return текст_офера, 0
    нова = правило(м.group(2))
    if нова == м.group(2):
        return текст_офера, 0
    return (текст_офера[:м.start(2)] + нова + текст_офера[м.end(2):]), 1


def _зняти_артикул_у_назві(текст_офера):
    """Артикул крамниці з `<name>` — див. блок вище."""
    return _правка_назви(текст_офера, назва_речі.зняти_артикул)


