def зони(t):
    """K-BOD-00/01: вектор співвідношень + маршрутизаційний ярлик.
    Ярлик віддається ОКРЕМИМ полем і явно позначений як маршрутизація: за конфлікту
    ярлика й зон корпус велить слухати зони, тож змішувати їх в одне поле не можна."""
    о = t["обхвати"]
    пл, гр, тал, ст = о["плечі"], о["груди"], о["талія"], о["стегна"]
    верх = max(пл, гр)
    δ = (ст - верх) / верх
    whr = тал / ст
    # Імпорт у виклику: `силует_пропорції` читає цей модуль на верху файлу.
    from силует_пропорції import бік_пари, похибка_виміру_тіла
    # похибка вимірів тіла — з тієї самої точки, що в боці пари й статурі (13917): категорія FFIT називається
    # лише понад похибку обох вимірів кожної різниці
    фігура = ФІГУРА.визначення(гр, тал, ст, о.get("високе_стегно"),
                               похибка=lambda вимір: похибка_виміру_тіла(t, вимір))
    талія_виражена = фігура["талія"]
    # A/V — бік пари: одне визначення `силует_пропорції.бік_пари` (межа 5 % верху, K-BOD-01), де бік названо
    # лише понад похибку обхватів обох боків; невідомий бік маршруту не дає (як у ролях зон і ребрі балансу).
    бік_п = бік_пари(t)["бік"]
    if бік_п == "низ": ярлик = "A"
    elif бік_п == "верх": ярлик = "V"
    elif бік_п is None: ярлик = "H/X межа"
    elif талія_виражена is True: ярлик = "X"
    elif фігура["категорія"] in ("Oval", "Diamond"): ярлик = "O"
    elif талія_виражена is False: ярлик = "H"
    else: ярлик = "H/X межа"
    return dict(вектор=dict(верх_проти_низу=round(δ, 3), WHR=round(whr, 3),
                            талія_виражена=талія_виражена,
                            талія_підстава=фігура["підстава"]),
                ярлик=ярлик, ярлик_це="маршрутизація до мапи ходів, не вердикт",
                застереження=фігура["чому"] + "; стан талії — з каскаду FFIT 2020 у дюймах; "
                             "маршрути A/V — за різницею верху й низу 5% понад похибку обхватів; "
                             "маршрут 8 і обхват середини не діагностуються")


