def тіло(зріст_см, обхвати_см, рівні_см=None, аксесуарні=None):
    """Профіль тіла + ЧЕСНИЙ ПРОВЕНАНС кожного рівня.

    `areas.профіль_тіла` ставить ВИСОТИ рівнів як фіксовані частки зросту
    (пах = 0.480·зріст завжди). Ширини там виводяться з реальних обхватів, а висоти —
    ні: це шаблон, однаковий для довгоногої і довгокорпусної жінки одного зросту.
    Доки це не названо, будь-яке правило про вертикальні пропорції МІРЯЄ ШАБЛОН і
    видає його за тіло.

    `рівні_см` — виміряні висоти окремих рівнів ({'пах': 76.0, 'талія': 101.5}).
    Кожен переданий рівень стає T1 (вимір рулеткою), решта лишається T3-шаблоном, і
    правила, що на них спираються, знають, на чому стоять.
    """
    базові = {k: v for k, v in обхвати_см.items() if k in areas.ПОТРІБНІ_ОБХВАТИ}
    проф = areas.профіль_тіла(зріст_см, базові)
    виміряні = set()
    # ЗНАЙДЕНО ПРИ ІМПЛЕМЕНТАЦІЇ, не при читанні джерел. У шаблоні areas.профіль_тіла
    # ширини ноги — частки обхвату стегон: коліно 0.42, литка 0.38. Тобто литка ЗАВЖДИ
    # вужча за коліно, і на всій нозі нижче стегон нема жодного локального максимуму.
    # Наслідок: найцитованіше застосування K-FIT-03 — «міді закінчується на найширшому
    # місці литки» — на цьому профілі не може спрацювати ніколи, бо найширшого місця
    # литки в профілі не існує. Порядок двох неатрибутованих констант вирішує долю
    # цілого правила. Тому обхвати ноги приймаються як ВИМІР, коли вони є.
    дод = {k: v for k, v in обхвати_см.items() if k not in areas.ПОТРІБНІ_ОБХВАТИ}
    # ── ОБХВАТИ, ЩО НЕ Є РІВНЯМИ ПРОФІЛЮ ─────────────────────────────────────
    # ЗНАЙДЕНО СКАНЕРОМ СИРІТ: `outfit.масштаб_особи` читає `обхвати["зап'ястя"]` для
    # K-SIL-06 — а зап'ястя НЕ Є рівнем фронтального профілю (профіль іде по осі тіла:
    # плечі, груди, талія…, і руки в ньому не існує). Тому спроба передати зап'ястя
    # ПАДАЛА ValueError, і «краща» гілка масштабу особи була не просто непід'єднана —
    # вона була НЕДОСЯЖНА. K-SIL-06 назавжди сидів на зростовому проксі й чесно про це
    # писав, але виправити це було неможливо без цієї правки.
    # Тепер такі обхвати приймаються як ПОЗАПРОФІЛЬНІ: вони не міняють геометрії
    # силуету, лише живуть у `обхвати` для правил, що їх питають.
    ПОЗАПРОФІЛЬНІ = ("зап'ястя", "шия", "біцепс", "передпліччя", "долоня", "стопа")
    поза = {k: v for k, v in дод.items() if k in ПОЗАПРОФІЛЬНІ}
    дод = {k: v for k, v in дод.items() if k not in ПОЗАПРОФІЛЬНІ}
    невідомі_обх = [k for k in дод if k not in {nm for nm, _, _ in проф}]
    if невідомі_обх:
        raise ValueError(f"обхвати для невідомих рівнів: {невідомі_обх}; "
                         f"позапрофільні приймаються окремо: {ПОЗАПРОФІЛЬНІ}")
    if дод:
        проф = [(nm, y, (дод[nm] / math.pi if nm in дод else w)) for nm, y, w in проф]
        виміряні |= {f"ширина:{k}" for k in дод}
    if рівні_см:
        невідомі = [k for k in рівні_см if k not in {nm for nm, _, _ in проф}]
        if невідомі:
            raise ValueError(f"нема таких рівнів: {невідомі}; є {[n for n,_,_ in проф]}")
        проф = [(nm, float(рівні_см.get(nm, y)), w) for nm, y, w in проф]
        виміряні = set(рівні_см)
        порядок = [y for _, y, _ in проф]
        if any(a < b for a, b in zip(порядок, порядок[1:])):
            raise ValueError("виміряні висоти рівнів порушують порядок згори вниз: "
                             f"{[(n, round(y,1)) for n, y, _ in проф]}")
    акс = {k: float(v) for k, v in (аксесуарні or {}).items()
           if k in АКСЕСУАРНІ_ВИМІРИ and v is not None}
    невідомі_акс = [k for k in (аксесуарні or {}) if k not in АКСЕСУАРНІ_ВИМІРИ]
    if невідомі_акс:
        raise ValueError(f"невідомі аксесуарні виміри: {невідомі_акс}; "
                         f"приймаються {АКСЕСУАРНІ_ВИМІРИ}")
    return dict(профіль=проф, зріст=float(зріст_см), обхвати=dict(обхвати_см),
                виміряні_рівні=виміряні, аксесуарні=акс,
                бракує_аксесуарних=[k for k in АКСЕСУАРНІ_ВИМІРИ if k not in акс],
                висоти={nm: y for nm, y, _ in проф},
                джерело_висот=("вимір+шаблон" if виміряні else "шаблон areas.РІВНІ (T3)"))


