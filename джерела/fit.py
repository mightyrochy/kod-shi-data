        # (c) відкриті вузькі точки — щиколотка з геометрії, яку контракт і так вимагає
        if О.get("відкрите_зап_ястя") or any(р.get("відкрите_зап_ястя") for р in речі):
            пройдені.append("вузька точка: зап'ястя відкрите (самозвіт)")
        else:
            краї_одягу = [min(р["верх_см"], р["низ_см"]) for р in речі
                          if р.get("слот") != "взуття"]
            взуття_верх = [max(р["верх_см"], р["низ_см"]) for р in речі
                           if р.get("слот") == "взуття"]
            відкрита = (min(краї_одягу) > щик + 0.5 and
                        (not взуття_верх or max(взуття_верх) <= щик + 0.5))
            (пройдені if відкрита else провалені).append(
                "вузька точка: щиколотка %s (край одягу %.0f см, рівень щиколотки %.0f)"
                % ("відкрита" if відкрита else "закрита", min(краї_одягу), щик))
        if not провалені:
            continue
        зн.append(_зн(
            "K-FIT-06", "strong",
            f"об'єм «{О['id']}» читається як завеликий одяг, не як свідомий хід",
            [О["id"]],
            "оверсайз законний за трьох маркерів; тут провалено %d з 3: %s%s%s"
            % (len(провалені), "; ".join(провалені),
               ("; пройдено: " + "; ".join(пройдені)) if пройдені else "",
               ("; не перевірено (нема входу): " + "; ".join(невідомі)) if невідомі else ""),
            ремонт=[м for пр, м in (
                ("плече", "розмір/крій із плечем по акроміону або конструктивно спущеним"),
                ("баланс", "одна прилегла річ поруч (skinny/pencil/fitted) або заправка"),
                ("вузька", "відкрити щиколотку або зап'ястя (підкот, коротший низ)"))
                if any(п.startswith(пр) for п in провалені)],
            запит=dict(слот=О.get("слот"), замість=О["id"],
                       крій="regular|relaxed",
                       чому="K-FIT-06: об'єм без маркерів свідомості"),
            вимір=float(len(провалені)), поріг=0.0, повна=C["оверсайз_маркери"],
            ламається="маркери — конвенція практиків без виміряних порогів; "
                      "«прилягає» береться з роду крою в таблиці T3; зап'ястя без "
                      "самозвіту невидиме, тож (c) вирішує щиколотка",
            примітка=("невідомі маркери не рахуються провалом: " + "; ".join(невідомі))
                     if невідомі else None))
