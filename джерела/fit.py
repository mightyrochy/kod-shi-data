# виміряними рівнями профілю, що й решта модуля.
# ТОЧКА ПОЯСА — ЗАПИС, А НЕ РІВЕНЬ (Е3-одна-величина ч31, п.7; рішення 06.11 «п.7: точка речі»). Рівень шаблону — точка
# ТІЛА, а «висока» / «середня» / «низька» — слово про те, де сидить пояс речі. База відносить посадку до природної талії й
# лінії ніг (тема-1:2721–2723), але де саме — не каже і застерігає, що ярлик не гарантує однакової ефективної посадки
# (тема-1:2734–2736); «середина між талією й високим стегном» для «середньої» — конвенція коду, не означення. Тому слово
# кладе точку на тіло через запис реєстру `похибка_вимірів_тіла.РЕЄСТР["точка_речі"]` (якорі — рівні, біля яких вона
# лежить; півширина — з джерела, а його нема): без півширини висота пояса — «невідомо» з якорем, а не число.
ПОСАДКА_ТОЧКА = {"висока": "пояс_висока", "середня": "пояс_середня", "низька": "пояс_низька"}
РІВЕНЬ_ПОЯСА = {посадка: _ПОХ.зона_точки_речі(точка) for посадка, точка in ПОСАДКА_ТОЧКА.items()}


def _висота_пояса(t, рівень):
    """Висота центра пояса над підлогою за рівнем із картки (середина якорів запису), або None. Це якір, а не
    вимір: похибку дає `_похибка_пояса`, і поки її нема, порівняння з ним — «невідомо»."""
    зона = РІВЕНЬ_ПОЯСА.get(str(рівень or "").strip().lower())
    if not зона:
        return None
    рівні = зона[0]
    h = t.get("висоти") or {}
    значення = [h[к] for к in рівні if h.get(к) is not None]
    return (sum(значення) / len(значення)) if len(значення) == len(рівні) else None


# ── МЕТА «ВИЩЕ» ПЕРЕМИКАЄ ЛІНІЮ ТАЛІЇ ──
# П8: «мета "довша лінія ніг" → завищена талія, ампір», доказ B, сила soft. Корпус
# має це як K-BOD-04 «petite → підняти талію», але маршрутизує ЯРЛИКОМ зросту (<163),
# і саме ярлик зняли разом із K-BOD-05 (K-BOD-00: зони, не ярлики). Тепер важіль
# вмикає не зріст, а її СЛОВО: мета `taller` («вище») — поле сценарію, лише з її слів.
# ЩО КОД МОЖЕ ПОРАХУВАТИ ТОЧНО: де сидить пояс на ЦЬОМУ тілі (рівень картки → виміряні
# рівні профілю) і на скільки см він нижче її талії. Норми «правильної» посадки тут
# нема й не треба: питання одне — чи пояс піднімає початок ніг, якого вона просила.
# Висока посадка — сама мета, правилу нема чого сказати. Посадки в картці нема —
# «утримано» з названим полем `посадка`, не мовчання (п.4).
ПОСАДКИ_НИЖЧЕ_ТАЛІЇ = ("середня", "низька")


def _похибка_пояса(t, рівень):
    """Похибка висоти пояса (`_висота_пояса`): півширина зони його точки (запис `точка_речі`) + найбільша з похибок
    рівнів-якорів. None — «невідомо»: півширини джерело не дає (так для кожної посадки) або похибка котрогось
    рівня невідома (високе стегно — без джерела)."""
    рівні, півширина = РІВЕНЬ_ПОЯСА.get(str(рівень or "").strip().lower()) or ((), None)
    п = [похибка_рівня(t, к) for к in рівні]
    return None if півширина is None or not п or any(х is None for х in п) else float(півширина) + max(п)


def посадка_пояса(t, речі, вище=False):
    """K-FIT-04. Важіль посадки й те, що його гасить; за плиткою «довша лінія»
    (`вище`, друга вісь мети) — і куди він стоїть."""
    if not (t.get("висоти") or {}).get("талія"):
        return []
    зн = []
    if вище:
        без_посадки = [р["id"] for р in речі
                       if р.get("слот") in ("низ", "комплект") and not р.get("посадка")]
        if без_посадки:
            _заяви_суті = [_ВМ.заява("rise_not_declared_for_taller_goal")]
            зн.append(_зн(
                "K-FIT-04", "утримано",
                _ВМ.суть_кодом(_заяви_суті, без_посадки), без_посадки,
                "мета «вище» перемикає лінію талії (П8): висока посадка починає ноги "
                "вище. Картка не називає посадки — поле `посадка` порожнє, тож вердикту "
                "нема, є брак входу",
                заяви=_заяви_суті, учасники=dict(речі=без_посадки)))
    низи = [р for р in речі if р.get("слот") in ("низ", "комплект") and р.get("посадка")]
    for н in низи:
        пояс = _висота_пояса(t, н["посадка"])
        if пояс is None:
            continue
        # верхні речі з ВИМІРЯНИМ краєм: дефолт слота тут не свідок (K-IO-05)
        верхи = [р for р in речі
                 if р.get("слот") in ("верх", "верхній_шар")
                 and р.get("край_джерело") in ("річ", "слово")
                 and р.get("низ_см") is not None and not р.get("заправлено")]
        if not верхи:
            # верху з виміряним краєм нема: схований пояс чи ні, невідомо, але КУДИ він
            # стоїть за метою — знає сама посадка, верх тут не свідок
            зн += _пояс_за_метою(t, н, пояс, вище)
            continue
        нижчий = min(верхи, key=lambda р: min(р["верх_см"], р["низ_см"]))
        край = min(нижчий["верх_см"], нижчий["низ_см"])
        сховано = пояс - край
        # ПОХИБКА ОБОХ БОКІВ (Е3-одна-величина п.6, ч14): пояс — рівень тіла як частка зросту (похибка
        # — із запису, `похибка_шаблону`; доки його нема — невідомо), край — розкид сітки, зона слова чи допуск.
        # Доти `сховано <= 0` судив точки: на 1 см «схований» ставав strong. Схований — лише понад
        # похибку обох; видно чи в межах похибки — важіль не названо вимкненим, і за метою «вище»
        # лишається спитати, КУДИ він стоїть (див. `_пояс_за_метою`), інакше правилу нема чого сказати
        _бік_пояса = бік(пояс, _похибка_пояса(t, н["посадка"]), край, похибка_краю(t, нижчий))
        # None — схований пояс чи ні, невідомо (точку пояса за посадкою база не означує, похибка висоти невідома):
        # правило не мовчить, а каже, що не судить (ч31, п.6(г), п.7; дошка 13992)
        if _бік_пояса is None:
            зн += _пояс_не_судить(н, нижчий)
        # −1 — пояс видно понад похибку: вимкненого важеля нема, мовчання правдиве; None — «утримано» вище, а
        # куди пояс стоїть за метою, знає сама посадка, верх тут не свідок
        if _бік_пояса != 1:
            зн += _пояс_за_метою(t, н, пояс, вище)
            continue
        зн.append(_зн(
            "K-FIT-04", "strong",
            "посадка «%s» нічого не робить: пояс схований верхом «%s» на %.0f см"
            % (н["посадка"], нижчий["id"], сховано),
            [н["id"], нижчий["id"]],
            "пояс визначає, ЗВІДКИ око починає ноги, і це головний важіль пропорції "
            "нога/тулуб. Пояс цієї речі сидить на %.0f см від підлоги (рівень «%s»), а "
            "край верху — на %.0f см, тобто нижче: око бачить край ВЕРХУ, не пояс. "
            "Важіль, за який заплачено вибором посадки, вимкнений"
            % (пояс, н["посадка"], край),
            заяви=[_ВМ.заява("waistline_hidden_by_top",
                             rise={"висока": "high", "середня": "mid", "низька": "low"}.get(н["посадка"], _ВМ.UNKNOWN),
                             hidden_cm=round(сховано))],
            ламається="правило НЕ каже, яка пропорція правильна, і популяційної норми "
                      "нога/тулуб тут нема навмисно — її знято 07.09.2026 разом із гілкою, "
                      "що на ній стояла (тема-1 §12: опублікований ефект на порядок менший "
                      "за роздільність входу, напрям для жінок не усталений). Твердження "
                      "тут внутрішньоособове: важіль або видно, або ні. Переклад рівня "
                      "картки у висоту — конвенція над ВИМІРЯНИМИ рівнями тіла, а не "
                      "наша шкала; і рівень картки — слово продавця, з власним "
                      "`посадка_джерело`",
            поріг=0.0, вимір=сховано, повна=15.0))
    return зн


def _пояс_не_судить(н, верх):
    """K-FIT-04 «утримано»: чи верх ховає пояс низу, невідомо — точка пояса за посадкою без джерела, її похибка
    невідома (або край верху в межах похибки). Заява `waistline_hidden_by_top_not_judged`; вердикту нема."""
    _заяви = [_ВМ.заява("waistline_hidden_by_top_not_judged",
                        rise={"висока": "high", "середня": "mid", "низька": "low"}.get(н["посадка"], _ВМ.UNKNOWN))]
    з = _зн("K-FIT-04", "утримано", _ВМ.суть_кодом(_заяви, [н["id"], верх["id"]]), [н["id"], верх["id"]],
            "чи верх «%s» ховає пояс посадки «%s», код не судить — де саме сидить пояс за словом посадки, база не "
            "каже, похибка його висоти невідома" % (верх["id"], н["посадка"]),
            заяви=_заяви, учасники=dict(речі=[н["id"], верх["id"]]),
            примітка="K-IO-05: схований пояс — лише понад похибку обох боків; інакше «невідомо»")
    з["сила_нп_джерело"] = "утримано: висота пояса за посадкою без джерела; вердикту «схований» нема"
    return [з]


def _пояс_за_метою(t, н, пояс, вище):
    """K-FIT-04 за метою «вище» (П8, soft): пояс нижче її талії — початок ніг нижчий,
    ніж вона просила. Висока посадка мовчить: це і є мета."""
    if not вище or н.get("посадка") not in ПОСАДКИ_НИЖЧЕ_ТАЛІЇ:
        return []
    нижче = t["висоти"]["талія"] - пояс
    # ОБИДВА БОКИ (п.6, п.7): талія — рівень тіла зі своєю похибкою, пояс — точка речі без джерела півширини. «Нижче»
    # — лише понад обидві; пояс не нижче (−1) — мовчання правдиве; None — «невідомо», правило не мовчить (дошка 13992)
    _бік_талії = бік(t["висоти"]["талія"], похибка_рівня(t, "талія"), пояс, _похибка_пояса(t, н["посадка"]))
    if _бік_талії == -1:
        return []
    if _бік_талії is None:
        _заяви = [_ВМ.заява("rise_below_waist_not_judged", rise={"середня": "mid", "низька": "low"}[н["посадка"]])]
        з = _зн("K-FIT-04", "утримано", _ВМ.суть_кодом(_заяви, [н["id"]]), [н["id"]],
                "мета «вище»: чи посадка «%s» ставить пояс нижче талії, код не судить — де саме сидить пояс за "
                "словом посадки, база не каже, похибка його висоти невідома (якір %.0f см від підлоги, талія %.0f см)"
                % (н["посадка"], пояс, t["висоти"]["талія"]),
                заяви=_заяви, учасники=dict(речі=[н["id"]]),
                примітка="K-IO-05: пояс нижче талії — лише понад похибку обох боків; інакше «невідомо»")
        з["сила_нп_джерело"] = "утримано: висота пояса за посадкою без джерела; вердикту «нижче талії» нема"
        return [з]
    return [_зн(
        "K-FIT-04", "soft",
        "мета «вище»: посадка «%s» ставить пояс на %.0f см нижче талії — ноги "
        "починаються нижче" % (н["посадка"], нижче),
        [н["id"]],
        "вона просила довшої лінії, і пояс визначає, ЗВІДКИ око починає ноги. Пояс "
        "цієї речі — на %.0f см від підлоги (рівень «%s»), її талія — на %.0f см. "
        "Висока посадка або завищена талія (ампір) підняли б початок ніг на ці %.0f см "
        "(П8: мета «довша лінія ніг» → завищена талія)"
        % (пояс, н["посадка"], t["висоти"]["талія"], нижче),
        заяви=[_ВМ.заява("rise_below_waist_for_taller_goal",
                         rise={"середня": "mid", "низька": "low"}[н["посадка"]],
                         below_waist_cm=round(нижче))],
        ламається="П8 стоїть на доказі B (практика стилістів, не вимір сприйняття); "
                  "культура й ІМТ зсувають оптимум. K-BOD-04 «petite → вища талія» тут "
                  "спрацьовує за МЕТОЮ, а не за ярликом зросту. Висота пояса за "
                  "посадкою — якір запису `точка_речі` (рівень талії чи високого стегна), "
                  "а не означення бази",
        поріг=0.0, вимір=нижче, повна=15.0)]


def перевірити(t, речі, intent=ТИПОВИЙ_НАМІР, мета=ТИПОВА_МЕТА, без_довжини=(), вище=False, *, прогін_руки=None):
    """Головний вхід модуля. `речі` — геометрія з розмірної таблиці:
      dict(id, слот, верх_см, низ_см, припуск?, заправлено?, пояс?,
           ширина_плеча_см?, плече?, відкрита_щиколотка?, відкрите_зап_ястя?)
    Повертає знахідки в тому самому контракті, що суд_образу.review (правило, сила,
    сила_нп, регістр, речі, чому, ремонт, запит_у_каталог, поріг, де_ламається).
    `без_довжини` — id верхніх речей, яких викликач відсіяв за браком довжини: K-SIL-02 називає їх
    у `діагностика` K-SIL-02, а не судить так, ніби їх нема."""
    for р in речі:
        for k in ("id", "слот", "верх_см", "низ_см"):
            if k not in р: raise ValueError(f"річ {р.get('id', '?')}: нема поля «{k}» — "
                                            "посадка міряє сантиметри, а не слоти")
    зн = (краї(t, речі, intent, мета, суд=True, прогін_руки=прогін_руки) + довжина_проти_зросту(t, речі)
          + поділ_образу(t, речі, intent, без_довжини) + плече(t, речі) + оверсайз(t, речі))
    вб = вертикальний_баланс(t)
    # ── K-BOD-05 УТРИМАНО НА ДОКАЗІ (тема-1 §12) ────────────────
    # Доти обидві гілки стояли на `нога_норма` = 0.480 — шаблонному числі без
    # джерела. Гілка «нема входу» просила в людини довжину внутрішнього шва й
    # обіцяла, що вимір «розблокує K-BOD-05/K-FIT-04/K-BOD-04»; гілка «є вхід»
    # видавала K-FIT-04 на силі `strong`, порівнюючи тіло з тим самим числом.
    # Корпус зняв підставу під обома: ефект на порядок менший за роздільність
    # входу, напрям для жінок не усталений. Тому питання знято (воно коштувало б
    # людині крок онбордингу й нічого не змінило б), а вердикт «довга нога /
    # довгий корпус» знято разом із нормою.
    _заяви_суті = [_ВМ.заява("vertical_balance_not_judged")]
    зн.append(_зн("K-BOD-05", "утримано",
                  _ВМ.суть_кодом(_заяви_суті),
                  [], вб.get("утримано_чому") or вб.get("чому"),
                  примітка="конфлікт K-BOD-04×05 тут не виникає: обидва правила — "
                           "застосування K-FIT-04 до однієї величини, і норми під "
                           "нею більше нема"))
    зн[-1]["заяви"] = _заяви_суті
    if вб["доступно"]:
        зн[-1]["вимір"] = вб["коефіцієнт_ноги"]
    зн += посадка_пояса(t, речі, вище)
    # ── K-FIT-04 НЕ СПИРАЄТЬСЯ НА ПОПУЛЯЦІЙНУ НОРМУ ─
    # Тут стояла реалізація під `if False:` — тридцять рядків мертвого коду,
    # лишених «щоб було видно в коді, а не лише в примітці». Видно з них було
    # тільки те, що рішення видалене не до кінця. Пояснення тримає цей коментар.
    #
    # Гілка рахувала відхилення `коефіцієнт_ноги` від норми 0.480 і видавала
    # напрям важеля («висока посадка» проти «середня або нижча»). Норму
    # `нога_норма` видалено: тема-1 §12 показала, що опублікований ефект
    # нога/тулуб на порядок менший за роздільність нашого входу, а для жінок
    # його напрям не усталений. Саме правило K-FIT-04 у корпусі лишається на
    # силі `strong` як МЕХАНІЗМ — знято тільки числове спрацювання.
    #
    # ЩОБ ПОВЕРНУТИ потрібна норма з джерелом (ANSUR II crotch height / stature
    # для жінок — звірка не проведена) АБО калібрування «посадка × вердикт» на
    # реальних тестувальницях.
    return зн


def звіт(t, речі, intent=ТИПОВИЙ_НАМІР, мета=ТИПОВА_МЕТА, *, прогін_руки=None):
    """Вимір + знахідки одним пакетом: композиторові потрібні обидва боки —
    що виміряно і що з цього випливає."""
    return dict(тіло=dict(зріст=t["зріст"], джерело_висот=t["джерело_висот"],
                          виміряні_рівні=sorted(t["виміряні_рівні"]) or None,
                          зони=зони(t), вертикальний_баланс=вертикальний_баланс(t)),
                краї=[dict(річ=р["id"], **край_проти_локального(t["профіль"], край(р), None,
                                                       похибка_краю(t, р), t.get("похибка_ширин")))
                      for р in речі if not (р.get("слот") == "взуття"
                                           and бік(край(р), похибка_краю(t, р), 0.0, 0.0) != 1)],
                знахідки=перевірити(t, речі, intent, мета, прогін_руки=прогін_руки),
                не_зроблено=[
                    "мапи ходів по типах тіла (K-BOD-02) — не реалізовані, є лише "
                    "діагностика зон, яка каже, яка мапа доречна",
                    "дефекти посадки з фото (K-FIT-02) — потрібен детектор на зображенні",
                    "K-FIT-06 реалізовано 24.08.2026; ЗАЛИШОК: маркер плеча без "
                    "ширини з розмірної таблиці лишається «невідомим» (у фідах її "
                    "майже нема), рукав/зап'ястя видно лише із самозвіту",
                    "жоден поріг не калібрований: усі T3, тому нічого не блокує"])


