# ЩО КАЖЕ КОРПУС (тема-1, FORCE strong): «Rise is the primary leg/torso proportion
# lever. The waistband defines where the eye starts the legs».
# ЩО БУЛО В КОДІ: нічого. Єдина числова гілка під цим ID порівнювала коефіцієнт
# ноги з ПОПУЛЯЦІЙНОЮ нормою 0.480, якої нема через відсутність джерела, —
