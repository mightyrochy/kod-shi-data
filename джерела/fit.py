def плече(t, речі):
    """K-FIT-01. Ширину плеча виробу з розмірної таблиці код не порівнює з тілом: тут вона —
    без входу («питання»), доки ширини плеча жінки в тому самому визначенні нема.

    ДВІ РІЗНІ ВЕЛИЧИНИ (рішення менеджера 06.11 п.3, ч14). Плече виробу крамниці міряють «шов–шов
    по спинці», а плече тіла тут — обхват плечей через π (`areas.профіль_тіла`: «ширина фронтальної
    проєкції ≈ обхват/π»): оцінка іншої величини, не вимір. Їхня різниця — не факт, тож доти заява
    `shoulder_width_vs_body` з `delta_cm` і вага `soft` для будь-якої різниці (ч10) знято: виміряна
    річ важила більше за невиміряну навіть за δ = 0. Моделі — лише виміряні числа: ширина плеча
    речі й обхват плечей тіла, без різниці; входу бракує — її ширини плечей по спинці."""
    зн = []
    обхват = (t.get("обхвати") or {}).get("плечі")
    for р in речі:
        ш = р.get("ширина_плеча_см")
        if ш is None: continue
        if р.get("плече") == "спущене_конструктивно": continue
        _заяви_суті = [_ВМ.заява("her_shoulder_width_not_measured", item_cm=round(float(ш), 1),
                                 **({"body_girth_cm": round(float(обхват), 1)} if обхват else {}))]
        з = _зн("K-FIT-01", "питання",
                _ВМ.суть_кодом(_заяви_суті, [р["id"]]), [р["id"]],
                "ширина плеча виробу %.1f см (шов–шов по спинці, розмірна сітка) — а її плеча в цьому "
                "визначенні код не знає: обхват плечей через π — інша величина, і різниця з ним — "
                "не факт. Сходиться плече чи ні, код не судить" % float(ш),
                примітка="K-IO-05: правило цитується лише з атрибутом, який воно перевірило",
                учасники=dict(речі=[р["id"]]))
        з["питання_людині"] = "Яка ширина ваших плечей по спинці, від плечової кістки до кістки (см)?"
        з["заяви"] = _заяви_суті
        з["навіщо"] = "розблокує K-FIT-01: плече виробу проти її плеча в тому самому визначенні"
        зн.append(з)
    return зн


def оверсайз(t, речі):
    """K-FIT-06. Оверсайз ≠ завеликий. Свідомий об'єм вимагає трьох маркерів:
    (a) чисте або конструктивно спущене плече, (b) баланс проти однієї прилеглої
    речі, (c) відкриті вузькі точки. Без усіх трьох річ читається як одяг не за
    розміром — і це дискримінатор, який взагалі дозволяє системі пропонувати
    оверсайз, а не фільтрувати його як провал посадки.

    УСІ ТРИ входи для дискримінатора вже є в контрактах: поле «плече» і ширина
    плеча — у контракті цього ж модуля, рід крою «прилягає» — у silhouette.КРОЇ,
    відкрита щиколотка — виводиться з тих самих верх_см/низ_см, які контракт і так
    вимагає. Тому правило не потребує додаткових даних.

    ЧЕСНІ МЕЖІ (правило 6): маркер без входу — «невідомий», і він НЕ рахується
    провалом: сила стоїть лише на відомо-провалених. Зап'ястя/рукав модуль не
    бачить (довжина рукава не в контракті) — відкриту вузьку точку вирішує
    щиколотка. Вимір квантований 0..3 — це рідна роздільність трьох маркерів,
    не бакет поверх неперервної шкали."""
    щик = t["висоти"]["щиколотка"]
    _пох_щик = похибка_рівня(t, "щиколотка")
    def _кр(р):
        """Крій речі; коли його нема — `припуск` як найближчий наявний замінник."""
        return O.крій_речі(р) or р.get("припуск")
    зн = []
    for реч in речі:
        if _кр(реч) != "oversized":
            continue
        провалені, невідомі, пройдені = [], [], []
        # (a) плече
        пл, ш = реч.get("плече"), реч.get("ширина_плеча_см")
        if пл == "спущене_конструктивно":
            пройдені.append("плече: спущене конструктивно")
        elif ш is not None:
            # Межі «сідає / з'їжджає» нема (`плече_допуск` знято, п.2 вид 1), а ширини її плеча
            # «шов–шов» нема теж (обхват через π — інша величина, ч14): маркер (a) невідомий,
            # у тексті — лише виміряне число речі; провалом невідоме не рахується.
            невідомі.append("плече: ширина виробу %.1f см шов–шов — її плеча в цьому визначенні "
                            "код не знає" % float(ш))
        else:
            невідомі.append("плече: ні мітки «спущене», ні ширини з розмірної таблиці")
        # (b) баланс проти прилеглої речі
        інші = [р for р in речі if р is not реч and р.get("слот") != "взуття"]
        роди = [(_СР.КРОЇ.get(_кр(р) or "", {}).get("рід"), р["id"]) for р in інші]
        if any(рід == "прилягає" for рід, _ in роди):
            пройдені.append("баланс: є прилегла річ (%s)" %
                            next(і for рід, і in роди if рід == "прилягає"))
        elif інші and all(рід is not None for рід, _ in роди):
            провалені.append("баланс: жодна інша річ не прилягає (усі — об'єм)")
        else:
            невідомі.append("баланс: крій частини речей невідомий")
        # (c) відкриті вузькі точки — щиколотка з геометрії, яку контракт і так вимагає
        if реч.get("відкрите_зап_ястя") or any(р.get("відкрите_зап_ястя") for р in речі):
            пройдені.append("вузька точка: зап'ястя відкрите (самозвіт)")
        else:
            # ПОХИБКА ОБОХ БОКІВ (ч14): доти `край > щик + 0.5` — пів сантиметра без джерела, а рівень
            # щиколотки — шаблон 0.060 зросту без похибки (рішення 06.11 «орієнтири тіла», п.4: рівень невідомий).
            # Відкрита чи закрита — лише понад похибку обох (`бік`); інакше маркер невідомий.
            одяг = [р for р in речі if р.get("слот") != "взуття"]
            взуття = [р for р in речі if р.get("слот") == "взуття"]
            найнижчий = min(одяг, key=lambda р: min(р["верх_см"], р["низ_см"]))
            край_одягу = min(найнижчий["верх_см"], найнижчий["низ_см"])
            над = бік(край_одягу, похибка_краю(t, найнижчий), щик, _пох_щик)
            взуття_боки = [бік(max(р["верх_см"], р["низ_см"]), похибка_краю(t, р), щик, _пох_щик)
                           for р in взуття]
            if над == -1 or any(б_ == 1 for б_ in взуття_боки):
                провалені.append("вузька точка: щиколотка закрита (край одягу %.0f см, рівень "
                                 "щиколотки %.0f)" % (край_одягу, щик))
            elif над == 1 and all(б_ == -1 for б_ in взуття_боки):
                пройдені.append("вузька точка: щиколотка відкрита (край одягу %.0f см, рівень "
                                "щиколотки %.0f)" % (край_одягу, щик))
            else:
                невідомі.append("вузька точка: край одягу %.0f см і рівень щиколотки %.0f см — "
                                "у межах похибки чи похибка рівня невідома" % (край_одягу, щик))
        if not провалені:
            continue
        # ── ЩО ЦЕ МІНЯЄ (правило 3) ─────────────────
        # before: · об'єм «светр оверсайз» читається як завеликий одяг, не як свідомий хід [0.33]
        #         · об'єм «светр оверсайз» читається як завеликий одяг, не як свідомий хід [0.5]
        # after:  · об'єм «светр оверсайз» завеликий, а не свідомий — плече по акроміону [0.33]
        #         · об'єм «светр оверсайз» завеликий, а не свідомий — поруч прилегла річ, відкрити щиколотку [0.5]
        # Старий рядок недієвий: він однаковий, коли з'їхало плече, і коли поруч
        # нема прилеглої речі, — а лагодяться ці два різними речами. Які саме
        # маркери провалено, уже стоїть у `провалені`; звідти ж нижче будується
        # `ремонт`, тому тут лише його коротка форма, без нових перевірок.
        _куди = ", ".join(м for пр, м in (
            ("плече", "плече по акроміону"),
            ("баланс", "поруч прилегла річ"),
            ("вузька", "відкрити щиколотку"))
            if any(п.startswith(пр) for п in провалені))
        _маркери = [к for пр, к in (("плече", "shoulder"), ("баланс", "balance"),
                                    ("вузька", "narrow_point"))
                    if any(п.startswith(пр) for п in провалені)]
        зн.append(_зн(
            "K-FIT-06", "strong",
            f"об'єм «{реч['id']}» завеликий, а не свідомий — {_куди}",
            [реч["id"]],
            "оверсайз законний за трьох маркерів; тут провалено %d з 3: %s%s%s"
            % (len(провалені), "; ".join(провалені),
               ("; пройдено: " + "; ".join(пройдені)) if пройдені else "",
               ("; не перевірено (нема входу): " + "; ".join(невідомі)) if невідомі else ""),
            запит=dict(слот=реч.get("слот"), замість=реч["id"],
                       крій="regular|relaxed",
                       чому="K-FIT-06: об'єм без маркерів свідомості"),
            вимір=float(len(провалені)), поріг=0.0,
            повна=float(len(C["оверсайз_маркери"])),
            ламається="маркери — конвенція практиків без виміряних порогів; "
                      "«прилягає» береться з роду крою в таблиці T3; зап'ястя без "
                      "самозвіту невидиме, тож (c) вирішує щиколотка",
            примітка=("невідомі маркери не рахуються провалом: " + "; ".join(невідомі))
                     if невідомі else None,
            заяви=[_ВМ.заява("oversize_reads_too_big", failed=_маркери)]))
    return зн


