def тіло(зріст_см, обхвати_см, рівні_см=None, аксесуарні=None):
    """Профіль тіла + ЧЕСНИЙ ПРОВЕНАНС кожного рівня.

    `areas.профіль_тіла` ставить ВИСОТИ рівнів як фіксовані частки зросту
    (пах = 0.480·зріст завжди). Ширини там виводяться з реальних обхватів, а висоти —
    ні: це шаблон, однаковий для довгоногої і довгокорпусної жінки одного зросту.
    Доки це не названо, будь-яке правило про вертикальні пропорції МІРЯЄ ШАБЛОН і
    видає його за тіло.

    `рівні_см` — виміряні висоти окремих рівнів ({'пах': 76.0, 'талія': 101.5}).
    Кожен переданий рівень стає T1 (вимір рулеткою), решта лишається T3-шаблоном, і
    правила, що на них спираються, знають, на чому стоять.
    """
    базові = {k: v for k, v in обхвати_см.items() if k in areas.ПОТРІБНІ_ОБХВАТИ}
    проф = areas.профіль_тіла(зріст_см, базові)
    виміряні = set()
    # ЗНАЙДЕНО ПРИ ІМПЛЕМЕНТАЦІЇ, не при читанні джерел. У шаблоні areas.профіль_тіла
    # ширини ноги — частки обхвату стегон: коліно 0.42, литка 0.38. Тобто литка ЗАВЖДИ
    # вужча за коліно, і на всій нозі нижче стегон нема жодного локального максимуму.
    # Наслідок: найцитованіше застосування K-FIT-03 — «міді закінчується на найширшому
    # місці литки» — на цьому профілі не може спрацювати ніколи, бо найширшого місця
    # литки в профілі не існує. Порядок двох неатрибутованих констант вирішує долю
    # цілого правила. Тому обхвати ноги приймаються як ВИМІР, коли вони є.
    дод = {k: v for k, v in обхвати_см.items() if k not in areas.ПОТРІБНІ_ОБХВАТИ}
    # ── ОБХВАТИ, ЩО НЕ Є РІВНЯМИ ПРОФІЛЮ ─────────────────────────────────────
    # ЗНАЙДЕНО СКАНЕРОМ СИРІТ: `суд_образу.масштаб_особи` читає `обхвати["зап'ястя"]` для
    # K-SIL-06 — а зап'ястя НЕ Є рівнем фронтального профілю (профіль іде по осі тіла:
    # плечі, груди, талія…, і руки в ньому не існує). Тому спроба передати зап'ястя
    # ПАДАЛА ValueError, і «краща» гілка масштабу особи була не просто непід'єднана —
    # вона була НЕДОСЯЖНА. K-SIL-06 назавжди сидів на зростовому проксі й чесно про це
    # писав, але виправити це було неможливо без цієї правки.
    # Тепер такі обхвати приймаються як ПОЗАПРОФІЛЬНІ: вони не міняють геометрії
    # силуету, лише живуть у `обхвати` для правил, що їх питають.
    ПОЗАПРОФІЛЬНІ = ("зап'ястя", "шия", "біцепс", "передпліччя", "долоня", "стопа")
    поза = {k: v for k, v in дод.items() if k in ПОЗАПРОФІЛЬНІ}
    дод = {k: v for k, v in дод.items() if k not in ПОЗАПРОФІЛЬНІ}
    невідомі_обх = [k for k in дод if k not in {nm for nm, _, _ in проф}]
    if невідомі_обх:
        raise ValueError(f"обхвати для невідомих рівнів: {невідомі_обх}; "
                         f"позапрофільні приймаються окремо: {ПОЗАПРОФІЛЬНІ}")
    # ПОХИБКА ШИРИН (Е3-одна-величина, п.6, ч19): ширини рівнів — обхват/π або частка обхвату, з яким рівень
    # зв'язано в шаблоні (`areas.профіль_тіла`); похибку кожному дає запис `похибка_вимірів_тіла` (самовимір
    # стрічкою) — крізь шаблон, збуренням кожного введеного обхвату на його похибку. Обхват, чиєї похибки запис
    # не знає, робить невідомою ширину лише тих рівнів, що від нього залежать (ширини від інших — відомі).
    введені = {**базові, **дод}

    def ширини_за(обх):
        пр = areas.профіль_тіла(зріст_см, {k: v for k, v in обх.items() if k in areas.ПОТРІБНІ_ОБХВАТИ})
        return {nm: (обх[nm] / math.pi if nm in дод else w) for nm, _, w in пр}

    збурення = []
    for k_, v_ in введені.items():
        е_ = _ПОХ.похибка_якщо_є("обхват", k_)
        δ_ = float(е_) if е_ else 1.0
        збурення.append(dict(обхват=k_, похибка=е_, крок=δ_, ширини=ширини_за({**введені, k_: v_ + δ_})))
    if дод:
        проф = [(nm, y, (дод[nm] / math.pi if nm in дод else w)) for nm, y, w in проф]
        виміряні |= {f"ширина:{k}" for k in дод}
    # РІВНІ БЕЗ ШИРИНИ (лінія плеча — акроміон; рішення 13.11 «плечі»): висота є, вузла профілю нема — ширини на ній
    # форма не питає. Висота — шаблон чи вимір, як у вузлів; порядок згори вниз звіряється разом із ними.
    без_ширини = {nm: y for nm, y in areas.висоти_рівнів(зріст_см).items() if nm in areas.РІВНІ_БЕЗ_ШИРИНИ}
    if рівні_см:
        невідомі = [k for k in рівні_см if k not in {nm for nm, _, _ in проф} and k not in без_ширини]
        if невідомі:
            raise ValueError(f"нема таких рівнів: {невідомі}; є {[n for n,_,_ in проф] + list(без_ширини)}")
        проф = [(nm, float(рівні_см.get(nm, y)), w) for nm, y, w in проф]
        без_ширини = {nm: float(рівні_см.get(nm, y)) for nm, y in без_ширини.items()}
        # `|=`, а не `=`: присвоєння СТИРАЛО щойно записані «ширина:литка» тощо.
        # Тіло з виміряним обхватом литки І виміряною висотою
        # паху звітувало лише про пах, тобто система казала «литку не міряли», коли
        # її міряли. Провенанс їде в `для_стиліста` і в пакет для моделі, отже це
        # не бухгалтерія — це неправда в матеріалі, на якому модель вирішує.
        виміряні |= set(рівні_см)
        за_ім = {**{nm: y for nm, y, _ in проф}, **без_ширини}
        порядок = [за_ім[nm] for nm in areas.ПОРЯДОК_РІВНІВ if nm in за_ім]
        if any(a < b for a, b in zip(порядок, порядок[1:])):
            raise ValueError("виміряні висоти рівнів порушують порядок згори вниз: "
                             f"{[(n, round(за_ім[n], 1)) for n in areas.ПОРЯДОК_РІВНІВ if n in за_ім]}")
    акс = {k: float(v) for k, v in (аксесуарні or {}).items()
           if k in АКСЕСУАРНІ_ВИМІРИ and v is not None}
    невідомі_акс = [k for k in (аксесуарні or {}) if k not in АКСЕСУАРНІ_ВИМІРИ]
    if невідомі_акс:
        raise ValueError(f"невідомі аксесуарні виміри: {невідомі_акс}; "
                         f"приймаються {АКСЕСУАРНІ_ВИМІРИ}")
    висоти = {nm: y for nm, y in sorted({**{nm: y for nm, y, _ in проф}, **без_ширини}.items(),
                                        key=lambda п: areas.ПОРЯДОК_РІВНІВ.index(п[0]))}
    не_на_своїй = {nm for nm in areas.рівні_на_нижній_межі() if nm in введені}
    return dict(профіль=проф, зріст=float(зріст_см), обхвати=dict(обхвати_см),
                виміряні_рівні=виміряні, аксесуарні=акс,
                бракує_аксесуарних=[k for k in АКСЕСУАРНІ_ВИМІРИ if k not in акс],
                висоти=висоти,
                похибка_висот={nm: (None if nm in виміряні else похибка_шаблону(nm, зріст_см))
                               for nm in висоти},
                # ширина з обхвату, намальована на нижній межі його рівня (обхват плечей — на пахві, а міряно вище;
                # щиколотка — на кісточці), стоїть не на своїй висоті: різниці місць джерело не дає — «невідомо»
                # (рішення 13.11 «плечі», п.2; п.2 рішення «джерела похибки»)
                похибка_ширин={nm: (None if nm in не_на_своїй else похибка_ширини(w, nm, збурення))
                               for nm, _, w in проф},
                збурення_ширин=збурення,
                джерело_висот=("вимір+шаблон" if виміряні else "шаблон areas.РІВНІ (T3)"))


# ═══════════════ ПОХИБКА ОБОХ БОКІВ ПОРІВНЯННЯ (Е3-одна-величина, п.6, ч14) ═══════════════
# Рішення менеджера 06.11 («факт замість межі», п.3): бік і різницю порівняння код називає лише
# понад похибку ОБОХ його боків; похибку одного виміру дає повтор або визнане джерело про той
# самий спосіб виміру, з посиланням; ні повтору, ні джерела — «невідомо».
#
# БІК ТІЛА: РІВЕНЬ ЯК ЧАСТКА ЗРОСТУ. Висоти рівнів — шаблон `areas.РІВНІ` (частка × її зріст), не її
# вимір. Похибка рівня — розкид того самого відношення «висота орієнтира / зріст» у визнаному обмірі
# (рішення менеджера 06.11 «джерела похибки вимірів тіла», п.3); її пише ОДНИМ записом із посиланням
# `джерела/похибка_вимірів_тіла.py`, а тут і в `силует_пропорції.похибка_виміру_тіла` вона читається з
# того запису, без копій чисел. Рівень, якого запис не має (підборіддя, високе стегно, щиколотка), —
# «невідомо» (None), і кожне порівняння такого рівня з краєм речі — «невідомо»; це правильна поведінка,
# а не вада (там само, п.4). Маківка й підлога — у записі з нулем: за означенням.
# Рівень, який жінка виміряла сама (`рівні_см`), — не шаблон; похибки самозаміру джерело не дало (None).

# БІК РЕЧІ, ЯКУ ДАНО ВИСОТОЮ НА ТІЛІ (`край_джерело="річ"`): виробничий допуск розмірної специфікації,
# тема-1 §13 — ±0.5″ (1.3 см) для casual, «below about 1.3 cm … the garment's own manufacturing noise
# dominates». Довжину виробу з сітки крамниці несе розкид між розмірами (`край_розкид_см`), слово
# довжини — півширина своєї зони (`композитор_річ.РІВЕНЬ_ЗОНА`).
ДОПУСК_ВИРОБУ_СМ = 0.5 * 2.54


def похибка_шаблону(рівень, зріст_см):
    """Похибка висоти рівня-шаблону на цьому зрості (см) або None — невідома.

    Розкид (1 SD, частка зросту) того самого відношення з запису `похибка_вимірів_тіла` × зріст;
    рівень без розкиду в записі — None."""
    частка = _ПОХ.похибка_якщо_є("рівень", рівень)
    return None if частка is None else частка * float(зріст_см)


def похибка_ширини(w, рівень, збурення):
    """Похибка ширини тіла на рівні профілю (см, 1 SD) або None — невідома: сума внесків введених обхватів —
    зміна ширини рівня від збурення обхвату на його похибку (запис `похибка_вимірів_тіла`, самовимір
    стрічкою). Обхват, чиєї похибки запис не знає, але від якого ширина рівня залежить, робить її невідомою."""
    разом = 0.0
    for з in збурення:
        зсув = abs(з["ширини"][рівень] - w)
        if зсув < 1e-9:
            continue
        if з["похибка"] is None:
            return None
        разом += зсув * з["похибка"] / з["крок"]
    return разом


def похибка_рівня(t, рівень):
    """Похибка висоти рівня тіла (см) або None — невідома."""
    return ((t or {}).get("похибка_висот") or {}).get(рівень)


def похибка_висоти(t, см):
    """Похибка висоти точки тіла між рівнями — та сама кусково-лінійна інтерполяція профілю
    (`ширина_на`), що дає ширину; невідома похибка сусіднього рівня робить невідомою й точку."""
    пох = (t or {}).get("похибка_висот") or {}
    проф = [(nm, y, float("nan") if пох.get(nm) is None else пох[nm]) for nm, y, _ in t["профіль"]]
    п = ширина_на(проф, см)
    return None if math.isnan(п) else п


def похибка_слова(t, слово, рівень=None):
    """Похибка висоти краю зі слова довжини: півширина зони слова + похибка рівнів тіла, якими
    її поставлено (`рівень` — коли читач ставить край на один рівень, а не в центр зони)."""
    зона = _КР.РІВЕНЬ_ЗОНА.get(слово)
    if not зона:
        return None
    ключі, розкид = зона
    рівні = [похибка_рівня(t, к) for к in ((рівень,) if рівень else ключі)]
    if розкид is None or any(п is None for п in рівні):
        return None
    return float(розкид) + max(рівні)


def похибка_краю(t, р):
    """Похибка висоти краю речі над підлогою (см) на цьому тілі — обидва її джерела: бік речі
    (розкид сітки, зона слова чи допуск виробу) і бік тіла (рівень, від якого край відкладено).
    None — похибка невідома (край зі слотового дефолту, сітка без розкиду, рівень без джерела)."""
    # джерело не поставлене — те саме правило, що в `композитор_річ.у_річ`: обидва краї в записі — «річ»
    дж = р.get("край_джерело") or ("річ" if "верх_см" in р and "низ_см" in р else None)
    if дж == "виріб":
        розкид, точка = р.get("край_розкид_см"), р.get("край_точка_виміру")
        рів = похибка_рівня(t, точка) if точка else None
        return None if розкид is None or рів is None else float(розкид) + рів
    if дж == "слово":
        # `край_розкид_см` слова — та сама півширина зони (`композитор_річ.у_річ`)
        return похибка_слова(t, р.get("довжина_рівень"))
    if дж == "річ":
        return ДОПУСК_ВИРОБУ_СМ
    return None


def бік(а, похибка_а, б, похибка_б):
    """Знак а − б, коли різниця більша за похибку обох боків: 1 (а вище/більше), −1 (нижче/менше);
    інакше — None, «невідомо»: різниця в межах похибки або похибка котрогось боку невідома."""
    if а is None or б is None or похибка_а is None or похибка_б is None:
        return None
    if а - б > похибка_а + похибка_б:
        return 1
    if б - а > похибка_а + похибка_б:
        return -1
    return None


def ширина_на(проф, см):
    """Ширина фронтальної проєкції тіла на висоті `см` над підлогою.
    Кусково-лінійна інтерполяція між рівнями — та сама геометрія, якою areas.площа_виробу
    інтегрує площу, тільки витягнута в окрему функцію: правилам краю потрібне саме
    значення на точці, а не інтеграл."""
    зріст = проф[0][1]
    if not (-1e-6 <= см <= зріст + 1e-6):
        raise ValueError(f"рівень {см:.1f} см поза тілом [0, {зріст:.0f}]")
    for i in range(len(проф) - 1):
        (_, y1, w1), (_, y2, w2) = проф[i], проф[i + 1]
        if y2 - 1e-9 <= см <= y1 + 1e-9:
            t = 0.0 if abs(y1 - y2) < 1e-9 else (см - y2) / (y1 - y2)
            return w2 + (w1 - w2) * t
    return проф[-1][2]


# `_максимум_у_вікні` → лабораторія/без_викликача.py (Н-02-02: ДОСЯЖНІСТЬ 13.09 — «ніхто»)


def _межі_зсуву(проф, край_см, вікно=None):
    """(низ, верх) у см від підлоги, де шукають опуклість під краєм і місце, куди його зсунути.

    `вікно=None` — ВІДРІЗОК ТІЛА МІЖ СУСІДНІМИ РІВНЯМИ ПРОФІЛЮ, у якому лежить край (край
    рівно на рівні — між сусідами цього рівня). Рівні профілю — анатомічні орієнтири
    (стегна, пах, коліно, литка, щиколотка), за якими й названо довжину речі («до стегна»,
    «до коліна», «до середини литки»): край, що лишився між тими самими орієнтирами, — та
    сама річ, і опуклість під ним — котрийсь із цих орієнтирів («the widest point of a zone
    (bust, hip, calf)», K-FIT-03, тема-4:263). Межі — з профілю цього тіла, не число сесії
    (доти — `вікно_краю` ±10 см, T3 «моя оцінка»). Межі між вузькими місцями (перша
    редакція ч10) губили локальність: на нозі без опуклої литки «зоною» ставало все від
    щиколотки до талії, і максимумом під халявою черевика виходили стегна (K-SHO-11).
    Явне `вікно` — ±см навколо краю."""
    зріст = проф[0][1]
    if вікно is not None:
        return max(0.0, край_см - вікно), min(зріст, край_см + вікно)
    рівні = [y for _, y, _ in проф]
    нижче = [y for y in рівні if y < край_см - 1e-9]
    вище = [y for y in рівні if y > край_см + 1e-9]
    return (max(нижче) if нижче else 0.0), (min(вище) if вище else зріст)


def _локальний_максимум(проф, край_см, вікно):
    """Вершина профілю у вікні, яка є САМЕ максимумом (ширша за обох сусідів), а не
    просто найбільшим значенням на відрізку. Різниця принципова: на монотонному схилі
    найбільше значення — це кінець вікна, і воно нічого не каже про опуклість тіла."""
    лоу, хай = _межі_зсуву(проф, край_см, вікно)
    вершини = []
    for i in range(1, len(проф) - 1):
        nm, y, w = проф[i]
        if not (лоу <= y <= хай): continue
        if w >= проф[i - 1][2] and w >= проф[i + 1][2] and (
                w > проф[i - 1][2] or w > проф[i + 1][2]):
            вершини.append((nm, y, w))
    if not вершини: return None
    return min(вершини, key=lambda v: abs(v[1] - край_см))


def край_проти_локального(проф, край_см, вікно=None, похибка_см=None, похибка_ширин=None):
    """K-FIT-03, ВИМІР. Дві попередні версії провалились на прогоні, і обидві — по-своєму:

      · v1 (дефіцит проти максимуму у вікні ±8 см) спрацьовувала на РІВНІЙ ділянці:
        на литці максимум вікна ≈ ширині краю, дефіцит ≈ 0 — і правило вимагало
        зсунути край там, де зсув не міняє нічого (8 см відстані, 0.09 см ширини);
      · v2 (перцентиль ширини в діапазоні ±20 см) навпаки ГУБИЛА локальний максимум:
        на литці в діапазон потрапляло стегно, і найширша точка литки тонула в ньому —
        тобто найцитованіше застосування правила (довжина міді) не спрацьовувало.

    Тепер міряються ДВІ величини, і обидві потрібні:
      близькість  — наскільки край злився з найближчим ЛОКАЛЬНИМ максимумом
                    (опуклість тіла: стегна, литка, груди), у частках ширини;
      звуження    — наскільки вужче найвужче ДОСЯЖНЕ місце у вікні зсуву.
    Правило має право говорити лише коли обидві виконані: край на опуклості І є куди
    його подіти. Це і є «не завершувати на найширшій точці зони» без двох патологій.

    ПОНАД ПОХИБКУ ОБОХ БОКІВ (Е3-одна-величина, п.6, ч19; рішення менеджера 06.11 «п.6: крок обчислення і
    два виміри тіла»). Відповіді `на_максимумі` й `важіль_є` дають порівняння, а не кроки інтерполяції під
    ними (`ширина_на`, `_межі_зсуву`, `_локальний_максимум` лише вибирають відрізок чи вікно), тож похибка
    обох боків іде крізь ці кроки до відповіді: `похибка_см` — похибка висоти краю (`похибка_краю`: річ і
    рівень тіла), `похибка_ширин` — {рівень: похибка ширини тіла, см} (`тіло()["похибка_ширин"]`).
    Відповідь — True чи False, коли вона та сама на всьому відрізку [край − похибка, край + похибка] і на всьому
    інтервалі ширин ± похибка; інакше й коли котроїсь похибки нема — None, «невідомо» (читач не бачить у
    ній ні «на опуклості», ні «поза нею»). Числа `близькість` і `звуження` лишаються виміряними фактами.
    """
    лоу, хай = _межі_зсуву(проф, край_см, вікно)
    w = ширина_на(проф, край_см)
    лок = _локальний_максимум(проф, край_см, вікно)
    точки = sorted({лоу, хай} | {y for _, y, _ in проф if лоу < y < хай})
    y_min = min(точки, key=lambda y: ширина_на(проф, y)); w_min = ширина_на(проф, y_min)
    звуження = (w - w_min) / w if w > 0 else 0.0
    близькість = None if лок is None else (лок[2] - w) / лок[2]
    на, важіль = _відповіді_понад_похибку(проф, край_см, вікно, похибка_см, похибка_ширин)
    return dict(край_см=round(край_см, 1), ширина_краю=round(w, 2),
                локальний_максимум=(None if лок is None else
                                    dict(рівень=лок[0], см=round(лок[1], 1),
                                         ширина=round(лок[2], 2))),
                близькість=None if близькість is None else round(близькість, 4),
                на_максимумі=на,
                звуження=round(звуження, 4), найвужче_см=round(y_min, 1),
                ширина_мінімуму=round(w_min, 2),
                важіль_є=важіль,
                вікно=вікно if вікно is not None else (round(лоу, 1), round(хай, 1)))


def _похибка_ширини_на(проф, похибка_ширин, см):
    """Похибка ширини тіла на висоті `см` — інтерполяція похибок двох сусідніх рівнів, як сама ширина;
    None — котрогось з них похибка невідома."""
    if похибка_ширин is None:
        return None
    п = ширина_на([(nm, y, float("nan") if похибка_ширин.get(nm) is None else похибка_ширин[nm])
                   for nm, y, _ in проф], см)
    return None if math.isnan(п) else п


def _три(відповіді):
    """Спільна відповідь на всіх розглянутих точках: True чи False, коли вони однакові, інакше None."""
    відповіді = set(відповіді)
    return відповіді.pop() if len(відповіді) == 1 and None not in відповіді else None


def _відповіді_в_точці(проф, y, вікно, похибка_ширин):
    """(на_максимумі, важіль_є) у точці `y` над інтервалами ширин ± похибка; None — котрогось інтервалу нема."""
    w, е_w = ширина_на(проф, y), _похибка_ширини_на(проф, похибка_ширин, y)
    лок = _локальний_максимум(проф, y, вікно)
    лоу, хай = _межі_зсуву(проф, y, вікно)
    точки = sorted({лоу, хай} | {r for _, r, _ in проф if лоу < r < хай})
    y_min = min(точки, key=lambda r: ширина_на(проф, r))
    w_min, е_min = ширина_на(проф, y_min), _похибка_ширини_на(проф, похибка_ширин, y_min)
    на = важіль = None
    if е_w is not None and лок is None:
        на = False                       # опуклості нема: порівнювати нема з чим
    if е_w is not None and лок is not None:
        е_лок = похибка_ширин.get(лок[0])
        if е_лок is not None:
            if 1 - (w - е_w) / (лок[2] + е_лок) <= C["на_максимумі"]:
                на = True                # навіть найдальший від опуклості край — у межах порогу
            elif 1 - (w + е_w) / max(лок[2] - е_лок, 1e-9) > C["на_максимумі"]:
                на = False               # навіть найближчий до опуклості край — за порогом
    if е_w is not None and е_min is not None and w - е_w > 0:
        if 1 - (w_min + е_min) / (w - е_w) >= C["звуження_мін"]:
            важіль = True
        elif 1 - (w_min - е_min) / (w + е_w) < C["звуження_мін"]:
            важіль = False
    return на, важіль


def _відповіді_понад_похибку(проф, край_см, вікно, похибка_см, похибка_ширин):
    """(на_максимумі, важіль_є) краю `край_см` ± `похибка_см`: відповідь та сама на кінцях відрізка похибки
    й на всіх рівнях профілю між ними (там змінюються вікно зсуву й сусіди), інакше — None."""
    if похибка_см is None or похибка_ширин is None:
        return None, None
    зріст = проф[0][1]
    низ, верх = max(0.0, край_см - похибка_см), min(зріст, край_см + похибка_см)
    точки = sorted({низ, край_см, верх} | {y for _, y, _ in проф if низ < y < верх})
    пари = [_відповіді_в_точці(проф, y, вікно, похибка_ширин) for y in точки]
    return _три(п[0] for п in пари), _три(п[1] for п in пари)


def вікно_краю(проф, край_см, вікно=None, крок=0.5, похибка_ширин=None):
    """РЕМОНТ: суцільні відрізки у вікні зсуву, де край уже НЕ на локальному максимумі
    й де тіло вужче за поточне місце. Це і є вихід у каталог — довжина виробу
    рахується з цих чисел. Відрізок береться лише коли обидві умови доведені понад похибку ширин
    (`похибка_ширин`, як у `край_проти_локального`): недоведена — не ремонт; цілі зсуву — не вимір
    (позицію цілі краєм не міряють), тож їхня похибка — лише ширин."""
    w0 = ширина_на(проф, край_см)
    е0 = _похибка_ширини_на(проф, похибка_ширин, край_см)
    лоу, хай = _межі_зсуву(проф, край_см, вікно)
    відрізки, поточний = [], None
    y = лоу
    while y <= хай + 1e-9:
        м = край_проти_локального(проф, y, вікно, 0.0, похибка_ширин)
        е_y = _похибка_ширини_на(проф, похибка_ширин, y)
        вужче = (е0 is not None and е_y is not None
                 and ширина_на(проф, y) + е_y <= (w0 - е0) * (1 - C["звуження_мін"]))
        ок = (м["на_максимумі"] is False) and вужче
        if ок and поточний is None: поточний = y
        if not ок and поточний is not None:
            відрізки.append((round(поточний, 1), round(y - крок, 1))); поточний = None
        y += крок
    if поточний is not None: відрізки.append((round(поточний, 1), round(хай, 1)))
    відрізки = [(a, b) for a, b in відрізки if b - a >= 1.0]
    відрізки.sort(key=lambda s_: min(abs(s_[0] - край_см), abs(s_[1] - край_см)))
    return відрізки


