def перевірити(t, речі, intent="conventional", мета="лестити"):
    """Головний вхід модуля. `речі` — геометрія з розмірної таблиці:
      dict(id, слот, верх_см, низ_см, припуск?, заправлено?, пояс?,
           ширина_плеча_см?, плече?, відкрита_щиколотка?, відкрите_зап_ястя?)
    Повертає знахідки в тому самому контракті, що outfit.review (правило, сила,
    сила_нп, регістр, речі, чому, ремонт, запит_у_каталог, поріг, де_ламається)."""
    for р in речі:
        for k in ("id", "слот", "верх_см", "низ_см"):
            if k not in р: raise ValueError(f"річ {р.get('id', '?')}: нема поля «{k}» — "
                                            "посадка міряє сантиметри, а не слоти")
    зн = (краї(t, речі, intent, мета) + поділ_образу(t, речі, intent) +
          плече(t, речі) + оверсайз(t, речі))
    вб = вертикальний_баланс(t)
    # ── K-BOD-05 УТРИМАНО НА ДОКАЗІ (07.09.2026, тема-1 §12) ────────────────
    # Доти обидві гілки стояли на `нога_норма` = 0.480 — шаблонному числі без
    # джерела. Гілка «нема входу» просила в людини довжину внутрішнього шва й
    # обіцяла, що вимір «розблокує K-BOD-05/K-FIT-04/K-BOD-04»; гілка «є вхід»
    # видавала K-FIT-04 на силі `strong`, порівнюючи тіло з тим самим числом.
    # Корпус зняв підставу під обома: ефект на порядок менший за роздільність
    # входу, напрям для жінок не усталений. Тому питання знято (воно коштувало б
    # людині крок онбордингу й нічого не змінило б), а вердикт «довга нога /
    # довгий корпус» знято разом із нормою.
    зн.append(_зн("K-BOD-05", "утримано",
                  "вертикальний баланс утримано на доказі, не на браку виміру",
                  [], вб.get("утримано_чому") or вб.get("чому"),
                  примітка="конфлікт K-BOD-04×05 тут не виникає: обидва правила — "
                           "застосування K-FIT-04 до однієї величини, і норми під "
                           "нею більше нема"))
    if вб["доступно"]:
        зн[-1]["вимір"] = вб["коефіцієнт_ноги"]
    if False:   # ── K-FIT-04 ЧИСЛОВА ГІЛКА ЗНЯТА РАЗОМ ІЗ НОРМОЮ ──────────────
        # K-FIT-04 («посадка пояса — головний важіль нога/тулуб») лишається в
        # корпусі на силі `strong` і НЕ видаляється: тема-4 тримає його як
        # механізм. Знято саме ЧИСЛОВЕ спрацювання, бо воно рахувало відхилення
        # від видаленої норми — тобто видавало напрям важеля («висока посадка»
        # проти «середня або нижча») з константи, яку корпус визнав непридатною.
        # ЩО ЦЕ МІНЯЄ НАД РЕАЛЬНОЮ РІЧЧЮ: людині з виміряним пахом система
        # більше не каже «беріть високу посадку» на підставі порівняння з 0.480.
        # ЩОБ ПОВЕРНУТИ: потрібна норма з джерелом (ANSUR II crotch height /
        # stature для жінок — звірка не проведена) АБО калібрування «посадка ×
        # вердикт» на реальних тестувальницях. Доти гілка мертва навмисно, і це
        # видно в коді, а не лише в примітці.
        δ = вб["відхилення"]
        if abs(δ) >= C["баланс_поріг"]:
            низи = [р for р in речі if р.get("слот") == "низ"]
            довгий_корпус = δ < 0
            зн.append(_зн(
                "K-FIT-04", "strong",
                "посадка пояса — головний важіль пропорції на цьому тілі",
                [р["id"] for р in низи],
                f"нога займає {вб['коефіцієнт_ноги']:.3f} зросту",
                ремонт=("висока посадка: пояс підіймає точку, де починається нога"
                        if довгий_корпус else
                        "середня або нижча посадка подовжує корпус; висока не "
                        "потрібна як компенсація"),
                запит=dict(слот="низ",
                           посадка=("висока" if довгий_корпус else "середня|низька"),
                           чому="K-FIT-04: баланс нога/корпус, виміряний по паху"),
                вимір=abs(δ), поріг=C["баланс_поріг"], повна=C["повна_баланс"],
                ламається="напрям важеля — конвенція практиків, і за "
                          "intent fashion-forward інверсія пропорції — свідомий хід",
                примітка="діє лише з виміряним пахом: на шаблонних висотах вісь "
                         "не існує, і правило мовчить (гілка вище)"))
    return зн


