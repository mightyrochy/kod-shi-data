# ═════════════ 8. ОДНА ВЕЛИЧИНА, КІЛЬКА ДЖЕРЕЛ, ГОЛОСУВАННЯ ═════════════
# УРОК ЧАСТИНИ XXI, ЗАСТОСОВАНИЙ ДО КОДУ, А НЕ ПЕРЕКАЗАНИЙ. Три правила теми читали
# ОДНУ геометрію через три атрибути й спрацьовували разом на одній людині в одному
# пальті — один геометричний факт важив утричі більше за будь-що інше в композиції.
# Корпус уже ловив цей режим провалу (R-FEED-06: рівномірне дублювання роздуває
# впевненість, а не доказ). Тому тут ОДИН вимір, ОДИН внесок, а атрибути стають
# ДЖЕРЕЛАМИ ОЦІНКИ тієї самої величини: беруться ті, що є у фіді, і НЕЗГОДА МІЖ НИМИ
# ЗМЕНШУЄ ВПЕВНЕНІСТЬ, а не додає ваги.
def _голосування(джерела):
    """(оцінка ∈ [−1, 1], впевненість ∈ [0, 1], розклад). Порожньо — None."""
    голоси = [(і, з) for і, з in джерела if з is not None]
    if not голоси:
        return None
    знач = [з for _, з in голоси]
    сер = sum(знач) / len(знач)
    незгода = (max(знач) - min(знач)) / 2.0 if len(знач) > 1 else 0.0
    впевненість = round(max(0.0, 1.0 - незгода) * min(1.0, len(знач) / 3.0), 2)
    return dict(оцінка=round(сер, 2), впевненість=впевненість,
                джерел=len(знач), розклад=dict(голоси),
                незгода=round(незгода, 2))


def плечова_вісь(речі, тіло=None):
    """K-OUT-28 (хутряний капюшон), K-OUT-39 (комір і крій рукава), K-OUT-40
    (знімний капюшон) — ТРИ важелі ОДНІЄЇ величини: скільки обʼєму додано біля
    плечей. Знак задає найширша зона тіла, і корпус її вже верифікував (тема 1)."""
    зн = []
    в = _верхній(речі)
    if в is None or not тіло:
        return зн
    проф = {nm: w for nm, _, w in (тіло.get("профіль") or [])}
    плечі, стегна = проф.get("плечі"), проф.get("стегна")
    if плечі is None or стегна is None:
        return зн
    # знак: +1 — обʼєм біля плечей ПОТРІБЕН (плечі вужчі за стегна), −1 — шкодить
    різниця = (стегна - плечі) / max(стегна, плечі)
    знак = max(-1.0, min(1.0, різниця * 10.0))
    джерела = []
    if в.get("опушка"):
        джерела.append(("хутряний капюшон (K-OUT-28)", 1.0))
    if в.get("комір") in ("шаль",) or в.get("рукав") == "реглан":
        джерела.append(("шаль/реглан помʼякшує лінію (K-OUT-39)", 1.0))
    if в.get("комір") == "ревер" or в.get("рукав") == "вшивний":
        джерела.append(("ревер/вшивний структурує торс (K-OUT-39)", -1.0))
    # ── K-OUT-40 СТОЇТЬ ДО ГОЛОСУВАННЯ, І ЦЕ НЕ ПОРЯДОК РЯДКІВ ──────────────
    # ЗНАЙДЕНО ПРОБОЮ: емісія стояла ПІСЛЯ перевірки «чи є хоч один важіль», тож
    # річ, у якої знімний капюшон — ЄДИНА конфігураційна ознака, не давала правилу
    # спрацювати ніколи. А це рівно той випадок, заради якого правило й записане.
    if в.get("капюшон_знімний"):
        зн.append(dict(_зн("K-OUT-40", "hint",
            "знімний капюшон — вісь КОНФІГУРАЦІЇ, як пояс", [_імʼя(в)],
            "річ зі знімним капюшоном проходить ОБИДВІ гілки плечової осі: з "
            "капюшоном для вузьких плечей, без нього для широких — «особливо тим, хто "
            "не хоче зайвого обʼєму біля горловини» (LuisaViaRoma). Це третій випадок "
            "після пояса (K-OUT-08) і стану застібки, коли ОДНА річ займає кілька "
            "позицій; тобто конфігурованість — не набір винятків, а власний КЛАС "
            "атрибутів",
            ремонт=["зняти капюшон, коли обʼєм біля плечей не потрібен"],
            ламається="одне джерело, одне речення. Знімність у фіді трапляється лише "
                      "словом у назві чи описі, і «капюшон знімний» проти «з "
                      "капюшоном» відрізняє тільки текст"),
            сила_нп=0.2, сила_нп_джерело="конфігурованість, не оцінка"))
    гол = _голосування(джерела)
    if гол is None:
        return зн
    узгодженість = round(гол["оцінка"] * знак, 2)
    правило = "K-OUT-28" if в.get("опушка") else "K-OUT-39"
    # ── «ПРАЦЮЮТЬ / ТЯГНУТЬ ПРОТИ» — ЦЕ ЗНАК, А НЕ ДІЯ ──────────────────────
    # ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026). Знак уже порахований
    # двічі — `знак` (де в людини найширше) і `гол["оцінка"]` (куди тягнуть
    # важелі речі), — а суть віддавала лише їхній добуток словами. У промпт їде
    # `суть` + `сила_нп`, тож ші бачила вирок і не бачила, ЩО саме зробити.
    # Зміряно на одному тілі (плечі вужчі за стегна) з двома пальтами:
    #   before (шаль + реглан):
    #     · важелі біля плечей працюють на баланс тому, де в цієї людини найширше [0.07]
    #   before (ревер + вшивний):
    #     · важелі біля плечей тягнуть проти тому, де в цієї людини найширше [0.07]
    #   after (шаль + реглан):
    #     · важелі біля плечей додають обʼєм; у стегнах ширше, ніж у плечах — лишити як є [0.07]
    #   after (ревер + вшивний):
    #     · важелі біля плечей знімають обʼєм; у стегнах ширше, ніж у плечах — додати обʼєму біля плечей [0.07]
    # Старий рядок недієвий тому, що «тягнуть проти» не каже, В ЯКИЙ БІК: два
    # протилежні провали (важіль додає обʼєм широким плечам / знімає його
    # вузьким) давали однакове речення з однаковим числом, а ремонт («інша річ
    # із протилежним важелем») до промпта не доходить.
    # ── «НАЙШИРШЕ» ПРИБРАНО: ЦЕ БУЛО ТВЕРДЖЕННЯ ПРО ТІЛО, ЯКОГО ТУТ НЕ МІРЯЛИ
    # (ревізія 08.09.2026). Перша редакція писала «найширше в цієї людини в
    # стегнах». `знак` порівнює РІВНО ДВА рівні профілю — плечі й стегна, — а
    # «найширше» — це вирок про всі рівні. Зміряно: тіло 168 з обхватами
    # плечі 96 / груди 118 / стегна 98 дає ширини 30.6 / 37.6 / 31.2, тобто
    # найширше в цієї жінки ГРУДИ, а речення казало ші «в стегнах». Тепер у
    # реченні стоїть та сама пара, яку правило й порівнює. Форми навмисно
    # відмінкові («у стегнах», «у плечах»): `graph._вузли_знахідки` чіпляє вузол
    # тіла за називним відмінком («стегна», «плечі») окремим словом, і називний у
    # суті додав би ребру вузол, якого воно доти не мало.
    # ── НУЛЬОВА ОЦІНКА — ЦЕ НЕ «ЗНІМАЮТЬ» (ревізія 08.09.2026) ──────────────
    # `_голосування` віддає СЕРЕДНЄ, і на шаль + вшивний рукав (+1 і −1) воно
    # рівно 0.0 — важелі гасять одні одних. Двійкове «додають/знімають» писало в
    # такому образі «знімають обʼєм», тобто називало напрям, якого нема. Рядок у
    # промпт не їде (сила_нп 0.0 відсікається `bridge._питання_або_нуль`), але
    # знахідка лишається реплікою в пакеті, а неправда в пакеті — та сама неправда.
    зн.append(dict(_зн(правило, "default",
        "важелі біля плечей %s; %s — %s"
        % ("додають обʼєм" if гол["оцінка"] > 0
           else "знімають обʼєм" if гол["оцінка"] < 0
           else "гасять одні одних",
           "у стегнах ширше, ніж у плечах" if знак > 0
           else "у плечах ширше, ніж у стегнах" if знак < 0
           else "у плечах і стегнах порівну",
           "лишити як є" if узгодженість >= 0
           else "прибрати обʼєм біля плечей" if знак < 0
           else "додати обʼєму біля плечей"),
        [_імʼя(в)],
        "плечі %.1f см проти стегон %.1f см; важелі, оголошені в речі: %s. Знак ЗАДАЄ "
        "НАЙШИРША ЗОНА: додавати обʼєм біля шиї, коли плечі вузькі, і не додавати, "
        "коли широкі. Правило не потребує власного калібрування — воно вішає нові "
        "важелі на ВЖЕ ВЕРИФІКОВАНУ вісь балансу зон (тема 1). ОДИН вимір, один "
        "внесок: три атрибути — це три ДЖЕРЕЛА оцінки, а не три правила"
        % (плечі, стегна, ", ".join(гол["розклад"]))
        + ("; джерела НЕ ЗГОДНІ між собою (незгода %.2f), тому впевненість знижена до "
           "%.2f — незгода зменшує впевненість, а не додає ваги"
           % (гол["незгода"], гол["впевненість"]) if гол["незгода"] else ""),
        ремонт=(["знімний капюшон проходить ОБИДВІ гілки (K-OUT-40): з капюшоном для "
                 "вузьких плечей, без нього для широких"] if в.get("капюшон_знімний")
                else ["інша річ із протилежним важелем біля шиї"]),
        ламається="LuisaViaRoma — комерційний гайд, і його інтерес у тому, щоб для "
                  "кожної фігури знайшовся товар; такі джерела схильні не мати випадку "
                  "«нічого не пасує». Приобличчева частина теми тримається на ОДНОМУ "
                  "джерелі рангу 5 (опис реальної носійки) — найкрихкіша частина файлу. "
                  "І реглан несе подвійне навантаження: тут помʼякшує вузьке плече, а "
                  "за K-OUT-33 позбавляє річ стану «накинуто»"),
        сила_нп=round(abs(узгодженість) * гол["впевненість"], 2),
        сила_нп_джерело="одна величина, %d джерел, голосування (частина XXI)"
                        % гол["джерел"]))
    _СЛ.запис(правило, "плечова вісь: одна величина, кілька джерел", "плечова_вісь",
              значення="оцінка %.2f × знак %.2f, впевненість %.2f"
                       % (гол["оцінка"], знак, гол["впевненість"]),
              сила=abs(узгодженість), напрям="баланс зон")
    return зн


def фронтальний_V(речі, тіло=None):
    """K-OUT-12 — глибина фронтального V: ОДНА неперервна змінна з трьома входами.

    Три входи міряють одну величину в РІЗНИХ ОДИНИЦЯХ (сантиметри висоти застібки,
    двійкова бортність, категорійний тип коміра), і як звести їх в одну шкалу — не
    сказано ніде. Тому це голосування, а не вимір, і так воно й називається.

    ПОЛЕ `застібка` ТУТ ЧИТАЄТЬСЯ ЛИШЕ ЗНАЧЕННЯМ «нема» (12.09.2026, наряд
    Н-V14-031). «Без застібки» — це вхід 1 у крайньому положенні: точки застібання
    не існує, фронт не сходиться ніде, і V обмежений лише коміром. А «на блискавці»
    входу тут НЕ ДАЄ І НЕ ДІСТАНЕ: пальто на блискавці БОРТІВ НЕ МАЄ, його фронт —
    інша геометрія, і підставити блискавку в голосування про глибину V означало б
    сплутати вісь застібки з віссю бортності. Це головний названий ризик наряду, і
    рішення записане тут, щоб наступний прохід не «дочитав» решту значень поля.
    """
    зн = []
    в = _верхній(речі)
    if в is None:
        return зн
    джерела = []
    if в.get("бортність") == "однобортне":
        джерела.append(("однобортне веде вертикаль (вхід 2)", 1.0))
    elif в.get("бортність") == "двобортне":
        джерела.append(("двобортне: більше тканини впоперек грудей (вхід 2)", -1.0))
    if в.get("комір") == "ревер":
        джерела.append(("V-подібний ревер (вхід 3)", 1.0))
    elif в.get("комір") == "стійка":
        джерела.append(("стійка — V завглибшки нуль (нульовий кінець осі)", -1.0))
    if в.get("висота_застібки_см") is not None:
        джерела.append(("висота точки застібання (вхід 1)", 1.0))
    elif в.get("застібка") == "нема":
        джерела.append(("без застібки: точки застібання не існує — фронт не сходиться "
                        "ніде, тобто вхід 1 у крайньому положенні", 1.0))
    гол = _голосування(джерела)
    if гол is None:
        return зн
    # ── ВИХІД ЛИШЕ ТОДІ, КОЛИ ВІДОМІ ГРУДИ АБО ДОВЖИНА ШИЇ ──────────────────
    має_вхід_тіла = bool(тіло and ((тіло.get("обхвати") or {}).get("підгрудна")
                                   or (тіло.get("аксесуарні") or {}).get("шия_см")))
    if not має_вхід_тіла:
        зн.append(dict(_зн("K-OUT-12", "питання",
            "глибина фронтального V порахована, а прикласти нема до чого",
            [_імʼя(в)],
            "оцінка глибини %.2f за %d джерелами (%s), але правило вмикається лише "
            "тоді, коли відомі ГРУДИ або ДОВЖИНА ШИЇ. Ні підгрудної, ні довжини шиї "
            "профіль тіла не містить, а вгадувати «повні груди» з обхвату грудей "
            "означало б видати одну цифру за дві"
            % (гол["оцінка"], гол["джерел"], ", ".join(гол["розклад"])),
            ремонт="запитати підгрудну (груди − підгрудна = повнота) або довжину шиї",
            ламається="жодного числа в усьому правилі: «нижче», «глибше», «нижче "
                      "грудей» — це напрями, і сантиметра не дає жодне джерело"),
            сила_нп=0.0, сила_нп_джерело="входу тіла нема"))
        _СЛ.запис("K-OUT-12", "V пораховано, входу тіла нема", "фронтальний_V",
                  значення="оцінка %.2f" % гол["оцінка"], сила=0.0, напрям="черга")
        return зн
    # ── ПОЛЮС ОСІ БЕЗ ДІЇ — ЦЕ ЯРЛИК, А НЕ ЗНАХІДКА ─────────────────────────
    # ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026). Голосування вже дало
    # ПОЛЮС (`гол["оцінка"]`), а суть віддавала саме слово полюса. У промпт їде
    # лише `суть` + `сила_нп` (`bridge._стислі_знахідки` → рядок
    # `pipeline.промпт_ремонту`), тож ші діставала іменник без вказівки, куди
    # рухати фронт. Зміряно на двох образах:
    #   before (однобортне + ревер):  · глибина фронтального V: вертикаль [0.67]
    #   before (двобортне + стійка):  · глибина фронтального V: полиця [0.67]
    #   after (однобортне + ревер):
    #     · фронт «пальто» тримає вертикаль — не застібати вище найповнішої точки [0.67]
    #   after (двобортне + стійка):
    #     · фронт «пальто» лягає полицею впоперек грудей — глибший V: нижча застібка або ревер [0.67]
    # Старий рядок недієвий тому, що «вертикаль» і «полиця» — назви кінців осі:
    # однакове число при протилежних полюсах, і жодного слова про те, що з цим
    # робити. Механізм («застібка вище найповнішої точки робить полицю; глибший
    # V подовжує шию») уже стояв у `чому`, куди ші не заглядає.
    зн.append(dict(_зн("K-OUT-12", "strong" if гол["впевненість"] >= 0.6 else "default",
        "фронт «%s» %s" % (_імʼя(в),
            "тримає вертикаль — не застібати вище найповнішої точки"
            if гол["оцінка"] > 0 else
            "лягає полицею впоперек грудей — глибший V: нижча застібка або ревер"),
        [_імʼя(в)],
        "оцінка %.2f за %d джерелами (%s). Застібка ВИЩЕ найповнішої точки перетворює "
        "вертикаль на ПОЛИЦЮ; глибший V відкриває більше шиї й ПОДОВЖУЄ її. Три "
        "атрибути — це три джерела ОДНІЄЇ величини, а не три правила: тримати їх "
        "окремо означало б рахувати один геометричний факт тричі"
        % (гол["оцінка"], гол["джерел"], ", ".join(гол["розклад"])),
        ламається="незалежних ліній ТРИ, а не чотири (Angie Cox і оглядовий матеріал "
                  "YLF — один ресурс, тобто один голос). І у фіді з трьох входів "
                  "надійно є лише бортність"),
        сила_нп=round(abs(гол["оцінка"]) * гол["впевненість"], 2),
        сила_нп_джерело="голосування трьох входів, не вимір: одиниці різні"))
    return зн
