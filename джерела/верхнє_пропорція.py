# `relaxed` сюди НЕ входить: у словнику це мʼякий торсовий крій без розширення
# донизу, і зарахувати його означало б розсунути правило на половину каталогу.
ОБʼЄМНІ_КРОЇ = ("wide", "flared", "culottes", "full", "pleated", "a-line", "oversized")


