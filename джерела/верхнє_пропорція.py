# КАНОНІЧНОГО словника `silhouette.КРОЇ` («wide», «flared», «culottes»,
# «a-line»…), і нормалізує старі українські написання ОДИН читач —
# `outfit.крій_речі` (СИНОНІМИ_КРОЮ). Тобто тут порівнювалось нормалізоване
# поле з ненормалізованими словами, та ще й не тими, що є ключами словника
