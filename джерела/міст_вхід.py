def _шкіра(d):
    """Шкіра приходить одним hex АБО списком точок (щока, лоб, щелепа).

    ЧОМУ СПИСОК, І ЧОМУ НЕ ТАК, ЯК ВОЛОССЯ. Це РІЗНІ речі, і плутати їх не можна.
    Кілька тонів волосся — ВЛАСТИВІСТЬ людини: мелірування справді несе крок
    світлоти, і цей крок іде в правило. Кілька точок шкіри — не властивість, а
    ПОВТОРНИЙ ЗАМІР однієї величини: обличчя не дає образу «крок світлоти
    задарма». Тому розкид шкіри НІКОЛИ не потрапляє в бриф — він говорить лише
    про якість виміру.

    НАВІЩО ВЗАГАЛІ. Заміряно на трьох профілях: одна точка на щоці несе ±8–14 L*
    похибки від тіні, відблиску й тонального, і на двох профілях із трьох ця
    похибка ПЕРЕКИДАЄ рівень контрасту (середній↔високий, низький↔середній), а
    рівень задає крок світлоти в брифі: 25 проти 45 проти 100 одиниць. Медіана
    трьох точок збила похибку з 8.9 до 1.0 L*.

    Медіана, а не середнє: одна точка в тіні — це викид, і середнє його тягне."""
    ш = d.get("шкіра")
    сп = [ш] if isinstance(ш, str) else [x for x in (ш or []) if x]
    return сп[:6]


def _медіана_lab(labs):
    """Покоординатна медіана списку Lab — одна точка з кількох замірів шкіри."""
    import statistics as _st
    return tuple(_st.median([l[i] for l in labs]) for i in range(3))


def _волосся(d):
    """Волосся приходить СПИСКОМ довільної довжини. Один hex — законний випадок
    (рівний однотонний колір), а не помилка. Кілька — теж законний: мелірування,
    балаяж, відрослі корені й сивина дають кілька кроків світлоти на голові, і
    outfit.контраст_особи це вміє (збирає всі риси з ключем на «волосся», рахує
    σ і, коли σ > step_min, каже: крок в образі вже є)."""
    в = d.get("волосся")
    сп = [в] if isinstance(в, str) else [x for x in (в or []) if x]
    return сп[:МАКС_ТОНІВ] or [d["шкіра"]]


def _зсув_волосся(labs, ціль_L):
    """Ручка світлоти рухає ВСІ пасма на ту саму дельту: інакше виправлення
    середньої світлоти знищило б розкид, тобто ту саму річ, заради якої
    пасма й питаються."""
    if ціль_L is None or not labs:
        return labs
    д = float(ціль_L) - labs[0][0]
    return [(max(3.0, min(97.0, L + д)), a, b) for L, a, b in labs]


def _features(d):
    """Риси людини з hex-входу: (F, шкіра_lab, волосся_labs, очі_lab, точки шкіри).

    Шкіра — медіана точок (`_шкіра`), волосся — усі пасма з зсувом світлоти
    (`_зсув_волосся`), кільце райдужки — окрема риса, коли подане."""
    точки = [cs.hx(x) for x in _шкіра(d)]
    ш = _медіана_lab(точки); о = cs.hx(d["очі"])
    вл = _зсув_волосся([cs.hx(x) for x in _волосся(d)], d.get("L_волосся"))
    if d.get("L_шкіра") is not None:
        ш = (float(d["L_шкіра"]), ш[1], ш[2])
    F = cs.features(ш, вл[0], о)
    for i, lab in enumerate(вл[1:], start=2):
        F = cs.перерахувати_рису(F, "волосся_%d" % i, lab, kind="волосся")
    # K-ECHO-01 / Zyla (24.08.2026): темне кільце райдужки зі стенда — окрема риса
    # «очі_кільце» (кандидат «її чорний»); «очі» лишається тілом райдужки.
    # П.14 (СТАНДАРТ §4): «невиміряний hex» тут не буває — `показ` кладе в це
    # поле лише те, що сам вийняв регуляркою `#[0-9a-fA-F]{6}` (`показ.html:2956`,
    # `к.кільце || null`), а порожнє значення відсіяно умовою. Тобто `except
    # Exception` не страхував вхід, а ховав би поломку `перерахувати_рису` —
    # рису «її чорний» (K-ECHO-01 / Zyla) мовчки втрачав би ВЕСЬ профіль.
    if d.get("очі_кільце"):
        F = cs.перерахувати_рису(F, "очі_кільце", cs.hx(d["очі_кільце"]), kind="очі")
    return F, ш, вл, о, точки


def _збірка(d, донорський=False):
    """dict із JS → (F, T, зріст, сценарій-kwargs)."""
    F0, ш, вл, о, _ = _features(d)
    в = вл[0]
    зріст = float(d["зріст"])
    об = {k: float(v) for k, v in d["обхвати"].items() if v not in (None, "")}
    if донорський:
        ш, в, о, об = Б.донор(ш, в, о, об)
        зріст = зріст - 12.0 if зріст >= 165 else зріст + 12.0
        # РОЗКИД НЕ ЗБЕРІГАЄТЬСЯ. Раніше зберігався, і через це правило
        # «волосся саме несе крок світлоти» стояло однаковим у B і C — тобто
        # плацебо на ньому було сліпе. Розкид — така сама властивість людини,
        # як і контраст, тож донор його теж вивертає: у донора волосся однотонне.
        F = cs.features(ш, в, о)
    else:
        F = F0
    # АКСЕСУАРНІ ВИМІРИ ЇДУТЬ ТИМ САМИМ ПАКЕТОМ (Н-V13-025). `fit.тіло` приймає
    # `аксесуарні=` від першого дня, `accessory` тримає на них цілу таблицю воріт
    # розміру (K-SHO-13/15, K-EYE-01, K-HAT-01, K-WCH-01, K-GLV-01), а сюди аргумент
    # не передавався — тобто ворота були недосяжні на живому шляху ВСІХ чотирьох рук
    # не через код правил, а через один пропущений аргумент. Нічого не чистимо й не
    # приводимо: `fit.тіло` сам відсіює `None`, сам зводить до float і сам кидає
    # ValueError на невідомому імені — один сторож, а не два розбіжні.
    T = ПС.тіло(зріст, об, аксесуарні=d.get("аксесуарні")) if len(об) >= 3 else None
    с = d.get("сценарій") or {}
    kw = {k: v for k, v in с.items() if v not in (None, "")}
    # ── МАКІЯЖ ЯК РИСИ ПРОФІЛЮ ────────────────────────────────────────────────
    # Кольори макіяжу дають ВЛАСНІ дуги тону — по одній на зону, без усереднення
    # (`colorspace.додати_макіяж`). Раніше макіяж входив у систему єдиним
    # прапорцем «є / нема» й міг лише підняти ліміт контрасту; його КОЛІР не
    # використовувався ніде.
    #
    # ДОНОР ВИВЕРТАЄ МАКІЯЖ ТЕЖ. Це не педантизм: рука C — плацебо, і будь-яка
    # властивість людини, яку донор ЗБЕРІГАЄ, робить сліпий тест сліпим саме на
    # цій осі. Проєкт уже наступав на це з розкидом волосся. Тут вивертається за
    # тим самим правилом, що й волосся в `brief.донор`: світлота макіяжу йде на
    # протилежний від шкіри кінець шкали, тон лишається (тон і є те, що правило
    # читає, — його підміна зробила б донора нерозпізнаваним як людину).
    мк = с.get("макіяж")
    if донорський and isinstance(мк, dict):
        _ц = 8.0 if ш[0] >= 50 else 92.0
        мк = {з: Б.перефарбувати_L(h, _ц) if isinstance(h, str) and h.startswith("#") else h
              for з, h in мк.items()}
    F, _дод = cs.додати_макіяж(F, мк)
    return F, T, зріст, kw


