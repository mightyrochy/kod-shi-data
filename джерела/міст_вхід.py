ІНШІ_БАРВИ = {"яскраві": "приглушені", "приглушені": "яскраві"}


БІЛИЙ_У_САМОЗВІТ = {"вершковий": "теплий", "оптичний": "холодний"}


def нормувати_елісітацію(вх):
    """Одна відповідь людини → два словники, які чекають РІЗНІ споживачі.

    `palette.тепло_з_елісітації` чекає білий як «вершковий/оптичний», а
    `palettes._hue` — той самий білий як «теплий/холодний». Обидва мовчать на
    чужому слові: перший не додає каналу, другий тихо рахує нуль. Контракт при
    цьому формально не порушено. Тому переклад живе в ОДНОМУ місці — тут, на межі.
    """
    в = dict(вх or {})
    драп = {k: в[k] for k in ("білий", "метал", "нейтралі") if в.get(k)}
    # СЛОВНИК ДРАПІРОВКИ → СЛОВНИК РАНГУ. `bases.температура_людини` чекає
    # метал ∈ {золото, срібло}, нейтраль ∈ {теплі, холодні}, білий ∈ {теплий,
    # холодний}; показ віддає метал «теплі/холодні», білий «золото/срібло», а
    # `нейтралі` в показі — про хрому (приглушені/яскраві), не про температуру.
    # Без перекладу всі три голоси стають None, і палітра рахується лише з фото.
    _МЕТАЛ = {"теплі": "золото", "теплий": "золото", "золото": "золото",
              "холодні": "срібло", "холодний": "срібло", "срібло": "срібло"}
    _БІЛИЙ = {"золото": "теплий", "теплий": "теплий", "вершковий": "теплий",
              "срібло": "холодний", "холодний": "холодний", "оптичний": "холодний"}
    if в.get("метал") in _МЕТАЛ:  в = dict(в, метал=_МЕТАЛ[в["метал"]])
    if в.get("білий") in _БІЛИЙ:  в = dict(в, білий=_БІЛИЙ[в["білий"]])
    сам = {}
    if в.get("метал"):  сам["метал"] = в["метал"]
    if в.get("білий"):  сам["білий"] = БІЛИЙ_У_САМОЗВІТ.get(в["білий"], в["білий"])
    if в.get("барви"):  сам["барви"] = в["барви"]
    # хрома: «нейтралі приглушені/яскраві» — це і є самозвіт про власні барви для
    # bases.ЦІЛЬ_ХРОМИ (6 / 22); без нього ціль стояла на 12 і всі кольорові основи
    # вилітали в «не радимо»
    if в.get("нейтралі") in ("приглушені", "яскраві") and not сам.get("барви_хрома"):
        сам["барви_хрома"] = в["нейтралі"]
    return dict(драп=драп, самозвіт=сам)


def нормалізувати_вхід(d):
    """Сирі відповіді драпіровки → два ключі входу, ОДИН раз на межі моста.

    Переклад мусить стояти на межі моста, а не лише в `запити`: показ шле
    `драп_сирий` усім ендпойнтам, тоді як `палітри` читає `самозвіт`, а
    `від_моделі` не читає жодного з двох. Інакше екран палітри й суддя сліпі до
    єдиного каналу, що не залежить від камери.

    Окрема функція потрібна тому, що `виклик` — диспетчер для JS, а частина
    ендпойнтів приходить у код повз нього (тести, прилади, `стенд_знімок`).
    Межа, яку можна обійти, — не межа.

    Явно поданий `самозвіт` сильніший за сирі картки: це те саме правило, що вже
    стояло в `запити`, і воно потрібне рукам експерименту, які подають самозвіт
    вивернутим (`_самозвіт(d, донорський=True)`).
    """
    if d.get("драп_сирий") and not d.get("самозвіт"):
        _е = нормувати_елісітацію(d["драп_сирий"])
        return dict(d, самозвіт=_е["самозвіт"], драп=_е["драп"])
    return d


def самозвіт(d, донорський=False):
    """Те, що людина сказала про себе, а не те, що видно на фото.

    Вісь colour contrast (K-CLR-01 §2) рахується з барвності волосся й ОЧЕЙ, але
    з телефонного фото не стверджується: надійність хроми 0.35 при порозі 0.5.
    Канон (K-PC-01) прямо приписує в цьому місці питати людину, а не вимірювати.
    Донор перекидає відповіді — це властивість особи, отже плацебо її вивертає."""
    с = dict(d.get("самозвіт") or {})
    if донорський:
        if с.get("барви"):
            с["барви"] = ІНШІ_БАРВИ.get(с["барви"], с["барви"])
        if с.get("метал"):
            с["метал"] = {"золото": "срібло", "срібло": "золото"}.get(с["метал"], с["метал"])
    return с


def застосувати_паспорт(d):
    """Паспорт випадку — єдине джерело випадку для коду, чотирьох рук, опису й журналу.
    Що не заповнене — з обраного сценарію (дефолти вже в pipeline.паспорт_з_json)."""
    п = d.get("паспорт")
    if not isinstance(п, dict):
        # ТИПОВЕ-1: і без паспорта замовчування форми (11:00, +18 °C, місце плитки) не стає її днем
        # для правил — та сама межа, що в `з_показу` (там паспорт мовчить, отже поле «невідомо»)
        _тип = {str(x) for x in ((d.get("сценарій") or {}).get("типові_поля") or ())}
        if _тип and isinstance(d.get("сценарій"), dict):
            return dict(d, сценарій={k: v for k, v in d["сценарій"].items()
                                     if k not in _тип or k not in СЦ.ПОЛЯ})
        return d
    # ── ПАСПОРТ ВІДДАЄ ВСЕ, ЩО НЕСЕ, А НЕ ТРИ ПОЛЯ ──────────────────────────
    # Злиття йде за оголошеним записом нагоди: паспорт переважає сценарій
    # (слова людини про цю подію — перші), а незнайоме не зникає мовчки. Це
    # зберігає, зокрема, `тривалість_год`, якою `outer.стан` рахує ціну стану.
    сц, _незнайомі = _ПН.з_показу(d.get("сценарій"), п)
    if _незнайомі:
        # не помилка й не мовчання: показ має право слати своє, але шов зобов'язаний
        # сказати, чого він не знає, — інакше наступне поле згине так само тихо
        сц["_незнайомі_поля"] = _незнайомі
    if п.get("ошатність"): сц["ошатність"] = list(п["ошатність"])
    # ── ПРОХАННЯ — НЕ ВЕТО ──────────────────────────────────────────────────
    # Тип, тканина чи принт від моделі стають межею лише тоді, коли слова жінки
    # заперечують саме цю річ. Перевіряє це код: слово вето мусить стояти у
    # клаузі заперечення (`паспорт_нагоди.клаузи_заперечення`). Межа діє в обох
    # каналах — у тексті вимог і в `жорстке_ні`, бо перший читає модель, а другий
    # фільтрує пул.
    # Кольори не проходять цей гейт: словник заперечень не розпізнає «не темного»,
    # хоча це справжня межа кольору. Вето поза словником заперечень лишається
    # видимим жінці й чекає на її підтвердження.
    # `паспорт_нагоди.вето_тверде` обчислює межі для всіх читачів. Якщо готового
    # поля нема, код перечитує слова, щоб збережений сценарій не втратив меж.
    _тв = _ПН.вето_чинне(п)
    _тверде = lambda k, w: str(w).strip().lower() in {str(x).strip().lower() for x in (_тв.get(k) or [])}
    # ПЕРЕКАЗ ПОЛІВ ПАСПОРТА — ОДНИМ СПИСКОМ (`пакет_моделі.рядки_переказу_полів`):
    # тут вони СКЛАДАЮТЬСЯ, бо текст вимог читає код (бриф, фільтр взуття `каблук.прохання`),
    # а в пакет рук 1–2 вони не їдуть — там ті самі факти вже стоять кодами
    # (`wishes`, `refusals`, `mood`, `jewelry`), і `випадок_для_пакета` знімає рівно ці рядки.
    вето = _ПН.вето_словами(п)
    вимоги = list(_ПМ.рядки_переказу_полів(п))
    if п.get("слова"): вимоги.append(_ПМ.ПІДПИС_ЇЇ_СЛІВ % п["слова"])
    # ПРОХАННЯ ПРО КАБЛУК — РЯДКОМ КОДУ (Ч-4): з ключів шару, не з її слів; його читає фільтр
    # взуття `каблук.прохання` у `міст_пакет` (той отримує лише текст вимог)
    _рядок_взуття = _КБ.рядок_прохання(_КБ.прохання_з_паспорта(п))
    if _рядок_взуття:
        вимоги.append(_рядок_взуття)
    # ШАР ТЕМА-6: слова «не хочу» →
    # `жорстке_ні` (profile.жорстке_ні_фільтр у композитор_придатні.придатні — абсолютний фільтр по
    # крою, тканині, кольору, типу, зоні, довжині, назві); зони → `вето` (outfit: правила
    # відкритих зон читають {"зони": [...], "ноги_вище_см": N}).
    _зони_словник = ("декольте", "спина", "руки", "плечі", "ноги", "живіт")
    _вето_обʼєкт = dict(d.get("вето") or {})
    _зони = [z for z in ((п.get("вето") or {}).get("зони") or []) if str(z).strip().lower() in _зони_словник]
    if _зони: _вето_обʼєкт["зони"] = sorted(set((_вето_обʼєкт.get("зони") or []) + [z.strip().lower() for z in _зони]))
    if п.get("ноги_вище_см"): _вето_обʼєкт["ноги_вище_см"] = п["ноги_вище_см"]
    # ── СЛОВО ВЕТО → ОСНОВИ КЛАСУ; ПЕРЕКОНАННЯ → ВЕТО ──────────────────────
    # Слово вето розширюється до класів лише в режимі «вето»
    # (`pipeline.ВЕТО_СЛОВА`). Переконання (K-LNG-04) приходить межею від мовного
    # шару (`beliefs` → `вето`) і словами ядра в `переконання`; інструкція «не
    # спростовувати» їде моделі у вимогах, бо це межа людини. Її слова тлумачить
    # лише мовна модель шару (Ч-4, аудит/ПРОДУКТ.md п.12).
    _жорстке = list(d.get("жорстке_ні") or [])
    # ТОЙ САМИЙ ПРЕДИКАТ, ЩО Й НА ТЕКСТІ ВИМОГ (`_тверде`): два канали
    # однієї межі мусять розходитись хіба що помилкою, а не двома міркуваннями.
    # ── КЛАС КОЛЬОРУ, СКАЗАНИЙ ПРО ОДИН СЛОТ, СЮДИ НЕ ЙДЕ  ────────
    # `жорстке_ні_фільтр` міряє річ, але слота межі не знає: «яскравий ВЕРХ … не
    # темного кольору» він зняв би з УСЬОГО образу — темні штани й темне взуття
    # разом із темним жакетом, тобто рівно та біда, яку слот і лікує. Свій слот
    # межа має в пулі (`пакет_моделі.жорстке_відсічення` читає `вето.слоти`), і
    # другий, ширший читач там лише зіпсував би вужчого. Клас БЕЗ слота сказаний
    # про весь образ — він іде сюди, як і всі інші слова, і фільтр читає його
    # виміром (`profile.жорстке_ні_фільтр`).
    _слоти_вето = _тв.get("слоти") or {}
    for k in ("типи", "тканини", "принти", "кольори"):
        for w in (п.get("вето") or {}).get(k, []):
            if _тверде(k, w) and not _слоти_вето.get(str(w).strip().lower()):
                _жорстке += _ПН.слова_вето(w)
    _переконання = [str(x).strip() for x in (п.get("переконання") or []) if str(x).strip()]
    if _переконання:
        _СЛ.запис("K-LNG-04", "belief_to_limit_no_refutation", "мовний_шар.beliefs",
                  значення=", ".join(_переконання), сила=None, напрям="канал вето/преференції")
        # рядок складається в одному місці (`пакет_моделі.ПЕРЕКОНАННЯ_РЯДОК`): `випадок_для_пакета`
        # знімає РІВНО його й ставить поле `переконання` (Ч-8)
        вимоги.append(_ПМ.ПЕРЕКОНАННЯ_РЯДОК % "; ".join(_переконання))
    вих = dict(d, сценарій=сц, вимоги="\n".join(вимоги) or (d.get("вимоги") or ""),
               намір=(п.get("намір") or d.get("намір") or "conventional"),
               випадок=_РБК.паспорт_рядком(п) or d.get("випадок") or "",
               жорстке_ні=sorted(set(str(w).strip().lower() for w in _жорстке if str(w).strip())) or None,
               вето=(_вето_обʼєкт or None),
               # ЇЇ МЕЖІ СЛОВАМИ — ТІ САМІ, ЩО «Не хоче» у вимогах: інакше опис
               # може назвати за компроміс річ, яку жінка прямо заборонила. Межі читають
               # опис і вибір (`ОПИС`, `ВИБІР`).
               межі=(вето or None))
    # ── ДРАПІРОВКА З ЧАТУ ЙДЕ ТИМ САМИМ ШЛЯХОМ, ЩО Й КАРТКИ (Т-08 крок 5, Р-3) ──
    # Відповіді з паспорта лягають у `драп_сирий` входу, звідки їх бере
    # `_нормалізувати_вхід`; картка, на яку жінка відповіла сама, переважає слово
    # з чату — це стимульна відповідь, а не переказ.
    if п.get("драп_сирий"):
        вих["драп_сирий"] = dict(п["драп_сирий"],
                                 **{k: v for k, v in (d.get("драп_сирий") or {}).items() if v})
    # ── ЇЇ РІЧ З ФОТО — ОСНОВА ОБРАЗУ, ЯКЩО ОСНОВИ ВОНА НЕ ОБИРАЛА ──
    # Тут, а не в пакеті: `запити`, `від_моделі` й `опис` беруть вхід саме звідси, тож
    # пул, суд і руки 3–4 стоять на одній основі. Без фото — жодного руху.
    if _РФ.закріплені(п.get("речі_з_фото")):
        _осн = _РФ.основа_з_речі(п.get("речі_з_фото"), вих.get("вибір_кольору"),
                                 lambda: збірка(нормалізувати_вхід(dict(вих)))[0],
                                 source=вих.get("source") or "uncontrolled", intent=вих["намір"])
        if _осн:
            вих["вибір_кольору"] = _осн
    return вих


def паспорт(вхід):
    """Виклик 0 показу. {сценарій, вимоги, профіль_текст?, історія?, паспорт?} → {промпт, схема};
    {json_моделі, сценарій, вимоги, вето?} → {паспорт, випадок, помилка_формату}.

    `історія` — стрічка чату екрана нагоди (`[{"хто": "людина|ші", "текст": …}]`),
    `паспорт` — поточний, частковий: обидва йдуть у промпт, і модель повертає
    паспорт ПОВНІСТЮ (Т-08 крок 1). Розбір — той самий `паспорт_з_json`, що й для
    одного повідомлення: чат — інший спосіб заповнити той самий паспорт.

    `вето` — чипи з екрана нагоди (`{"зони": [...]}`). Вони їдуть у розбір, а не
    повз нього: межу, яку людина поставила руками, не має права зняти ні мовчання
    моделі, ні валідний JSON без поля `вето` (Т-09). `помилка_формату` — причина
    невдалого розбору окремим полем: показ вкладає її в другу спробу (Н-V07-022) і
    називає жінці те, що сталось, замість мовчазного дефолта.

    `фото_речей` — фото речей нової репліки ([{ід, ширина, висота}]); самі
    зображення показ кладе в той самий виклик моделі. Їх читають і промпт (абзац про
    річ), і розбір (`речі_з_фото` паспорта).
    """
    d = _json.loads(вхід) if isinstance(вхід, str) else вхід
    if d.get("json_моделі") is not None:
        # ПАСПОРТ ЇДЕ І В РОЗБІР: показ шле його в обидва виклики того самого
        # ендпойнта (`паспортПоРозмовіП.база`). Так відповіді про драпіровку
        # зберігаються між ходами, а плитка, змінена рукою, переважає здогад моделі.
        # Обидва рішення — в одному парсері.
        п = _ПН.паспорт_з_json(d.get("json_моделі"), d.get("сценарій") or {}, d.get("вимоги") or "",
                               d.get("вето"),
                               паспорт_досі=(d.get("паспорт") if isinstance(d.get("паспорт"), dict) else None),
                               драп=(d.get("драп_сирий") or d.get("драп") or None),
                               фото=(d.get("фото_речей") or None))
        # ДВА РЯДКИ ВИПАДКУ МАЮТЬ РІЗНИХ ЧИТАЧІВ: `випадок` — коди для моделі й
        # звіту власника, `випадок_людині` — зрозумілий жінці текст над картками.
        return _json.dumps(dict(паспорт=п, випадок=_РБК.паспорт_рядком(п),
                                випадок_людині=_ПН.паспорт_рядком_людині(п),
                                # ШМАТКИ З КЛЮЧАМИ — поруч із рядком (Л-9): показ вішає
                                # піктограму на ключ поля, а не на позицію шматка (п.12).
                                випадок_шматки=_ПН.паспорт_шматками_людині(п),
                                помилка_формату=(п.get("помилка_формату") or "")),
                           ensure_ascii=False, default=str)
    return _json.dumps(dict(промпт=_ПН.промпт_паспорта(d.get("сценарій") or {}, d.get("вимоги") or "",
                                                       d.get("профіль_текст") or "",
                                                       історія=(d.get("історія") or None),
                                                       паспорт=(d.get("паспорт")
                                                                if isinstance(d.get("паспорт"), dict) else None),
                                                       драп=(d.get("драп_сирий") or d.get("драп") or None),
                                                       фото=(d.get("фото_речей") or None)),
                            схема=_ПН.СХЕМА_ПАСПОРТА,
                            # ВИБІРКА ПОРУЧ ІЗ ПРОМПТОМ, ЯК У МОВНОГО ШАРУ (М-6):
                            # чим семплити виклик 0, вирішує ОГОЛОШЕННЯ задачі
                            # (`збирач_промптів.ВИБІРКИ`), а не те, що стоїть у провайдера.
                            вибірка=_ЗП.вибірка(_ПН.ПАСПОРТ)), ensure_ascii=False)


def довідник(_вхід=None):
    """Нагоди, місця й дрес-коди — РІВНО ті ключі, з яких рахує `формальність.сценарій`.

    `_вхід` НЕ ЧИТАЄТЬСЯ СВІДОМО: диспетчер `bridge.виклик` кличе КОЖЕН ендпойнт як
    `функція(вхід)`, тож сигнатура однакова в усіх десяти; довідник же той самий для
    будь-якої жінки — він про таблицю, не про неї.

    Стенд і код мусять користуватися однією таблицею значень. Інакше слово поза
    таблицею мовчки падає у «невідоме середовище — широкий дефолт 3–6», правила
    формальності не спрацьовують, а журнал приписує їм вердикт. Тому список у
    стенді будується з цієї таблиці, а вільні слова людини ші зводить у її ключі.

    Ручний вибір формальності — це `дрес_код`: єдине місце, де людина ставить
    діапазон САМА, повз виведення з нагоди й місця.

    ЖИВИЙ, А НЕ КОПІЙОВАНИЙ. Таблицю будує `pipeline.довідник` (межі — з
    `outfit`, слова — `ДОВІДНИК_ПІДПИСИ`), збирач підставляє її в показ на місце
    плейсхолдера, промпт паспорта дає моделі ті самі ключі, а цей ендпойнт віддає
    її ж тому, хто спитає з JS."""
    return _json.dumps(_ПН.довідник(), ensure_ascii=False)


def індекс_гілки(розвилка, гілка, схема):
    """Індекс обраної гілки в розвилці ЦЬОГО пакета.

    Ім'я сильніше за номер: номер — це позиція в переліку, який під різними
    намірами різний, а ім'я те саме скрізь. Коли імені нема (CLI, стенд,
    сценарій без імені), використовується запасний шлях — номер із
    затиском по довжині. Коли ім'я є, але в розвилці його нема (схема зникла з
    корпусу), теж номер: мовчки підставляти нуль було б вибором за людину."""
    if схема:
        for i, г in enumerate(розвилка):
            if г["схема"] == схема:
                return i
    return None if гілка is None else min(гілка, len(розвилка) - 1)


