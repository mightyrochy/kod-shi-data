# Оголошення стоїть поруч із кодом, що читає hex (`_шкіра`, `_волосся`, `_features`).
# Даних у виклику, крім фото, нема, тому промпт сталий: його складає збірка
# (`build_артефакт`, плейсхолдер `__ПРОМПТ_КОЛІР_ПОКАЗУ__`), а не телефон — інакше
# перше зчитування чекало б Pyodide. Відповідь розбирає показ (`розібратиКолір`).
# ВІДПОВІДЬ — JSON за власним скелетом:
