def входи_чекліста(речі, тривалість_год=None):
    """Які входи аксесуарного чекліста є на ЦЬОМУ образі. Значення — bool.

    Ключі — рівно ті, що їх називає `суд_образу.ЧЕКЛІСТ_АКСЕСУАРІВ`; пояснення,
    ЧОГО бракує, стоїть у `ВХОДИ_ЧЕКЛІСТА` поруч і їде в чекліст разом зі станом,
    бо «без входу» без назви поля — це та сама тиша, тільки з алібі."""
    речі = list(речі or ())
    є = lambda сл: any(р.get("слот") == сл for р in речі)
    колготки = [р for р in речі if р.get("слот") == "колготи"]
    return {
        "рукавички в образі": є("рукавички"),
        "колготки з DEN": any(р.get("den") is not None for р in колготки),
        "колготки зі світлотою": any(р.get("L") is not None for р in колготки),
        # масштаб рис не міряє ніщо: значення стале й False НЕ ЗА ЗАМОВЧУВАННЯМ, а
        # за виміром — запис `БЕЗ_ВХОДУ["K-SCL-01"]` називає блокер поіменно
        "масштаб рис обличчя": False,
        "ланцюг і горловина": (any(р.get("ланцюг_см") is not None for р in речі
                                   if р.get("слот") in ЛАНЦЮГОВІ_СЛОТИ)
                               and any(р.get("виріз_тип") or р.get("край_джерело") == "річ"
                                       for р in речі
                                       if р.get("слот") in ("верх", "сукня", "комплект"))),
        "ремінь сумки": any(р.get("ремінь_см") is not None for р in речі),
        "конструкція низу взуття": any(р.get("ремонтопридатна") is not None for р in речі
                                       if р.get("слот") == "взуття"),
        "тривалість нагоди": тривалість_год is not None,
        "пул зі слотами-партнерами": any(р.get("ціна_ранг") is not None for р in речі),
        # оправа — риса ОСОБИ, не річ образу; сюди вона потрапити не може за
        # побудовою, і False тут — вимір, а не дефолт
        "оправа в профілі": False,
    }


