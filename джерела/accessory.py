def подовження_ноги(t, речі):
    """K-SHO-09. Подовження ноги — ДВОБІЧНА ціль, а не монотонна преференція.

    ЩО ЦЕ МІНЯЄ (before/after). before — «нюд подовжує» як одностороння перевага:
    нюдова пара завжди вище в ранзі. after — ціль формулюється як ПРОПОРЦІЯ
    торс : нога відносно виміряної пропорції ЦІЄЇ людини, і правило МІНЯЄ ЗНАК для
    довгоногих: там подовження ноги працює проти, а не за.

    ЦЕ ПРАВИЛО ІСНУЄ ЩОБ ЗАБОРОНИТИ ЕВРИСТИКУ, не щоб додати ще одну. «Нюд завжди
    краще» — саме той хід, який система зробила б сама.

    ⚠ І САМЕ ТОМУ ВОНО ПОКИ ЩО ВИХОДИТЬ ПИТАННЯМ. Вимір показав: `fit.тіло` віддає
    висоту паху з ШАБЛОНУ `areas.РІВНІ` (нога = 0.480·зріст для всіх), доки висота
    паху не виміряна. На шаблоні пропорція однакова в КОЖНОЇ людини — отже знак
    ніколи не зміниться, і правило вироджується назад в ту саму одностороння
    евристику, яку мало заборонити, тільки з виглядом виміру. Це блокер K-BOD-05,
    і він уже стоїть у реєстрі; правило чекає на нього, а не вдає роботу.
    """
    if not t:
        return []
    взуття = [р for р in речі if р.get("слот") == "взуття"]
    if not взуття:
        return []
    # ⚠ ПЕРША ВЕРСІЯ ПИТАЛА `"шаблон" in джерело_висот` — і рядок ВИМІРЯНОГО тіла
    # це "вимір+шаблон", тобто теж містить «шаблон». Правило лишалось питанням
    # НАВІТЬ КОЛИ пах виміряно, і знак не міняв ніколи. Питати треба про КОНКРЕТНИЙ
    # рівень, від якого залежить це правило, а не про загальний рядок походження:
    # тіло майже завжди «вимір+шаблон», бо частину рівнів міряють, а частину ні.
    виміряні = set(t.get("виміряні_рівні") or ())
    шаблон = "пах" not in виміряні
    пах = (t.get("висоти") or {}).get("пах")
    зріст = t.get("зріст")
    if пах is None or not зріст:
        return []
    частка = пах / зріст
    if шаблон:
        # ФОРМУЛЮВАННЯ — ЗА САМИМ K-SHO-09 (07.09.2026). Корпус у CHANGES цього ж
        # правила приписує: «the target is stated as torso : leg proportion relative
        # to this person's measured proportion». Код тримав механізм правильно в
        # `чому`, а в `суть` писав народне «подовження ноги» — і це [зона тіла як
        # обʼєкт ефекту] без goal-ініціації людини, тобто R-LNG-01 (`hard`).
        # Порушення не вилазило рівно тому, що це відро не збирав ніхто: мовний
        # гейт його не бачив (див. `pipeline`, збір знахідок обходом).
        return [dict(_зн("K-SHO-09", "питання",
            "пропорція торс : нога не рахується — висота паху взята з шаблону",
            [в.get("назва") or в.get("id") for в in взуття],
            "ціль — пропорція торс : нога ВІДНОСНО пропорції цієї людини, і для "
            "довгоногих правило міняє знак. Але висота паху взята з шаблону "
            "(нога = %.3f·зріст У ВСІХ), тож знак не зміниться НІ В КОГО, і правило "
            "виродилось би назад в одностороннє «нюд завжди подовжує» — рівно ту "
            "евристику, яку воно й мало заборонити" % частка,
            ремонт="виміряти висоту паху (або довжину кроку) — один вимір знімає блокер "
                   "K-BOD-05 одразу для кількох правил",
            ламається="правило, що спирається на популяційну середню, виглядає як вимір "
                      "і ним не є — це найнебезпечніша форма, бо її не видно у виводі"),
            сила_нп=0.0, сила_нп_джерело="входу нема (висота паху не виміряна)")]
    # ── виміряна пропорція: ціль стає двобічною ──────────────────────────────
    НЕЙТРАЛЬНА = 0.48          # [конвенція] середина шаблону, не вимір
    відхил = частка - НЕЙТРАЛЬНА
    # Той самий переклад у мову механізму, що й вище: напрям — це куди рухається
    # пропорція торс : нога відносно середини, а не «що робиться з ногою».
    # `далі_від_середини` — той самий знак, що вже стояв у цьому ж тернарнику,
    # винесений в імʼя: його читає ще й суть (див. блок ЩО ЦЕ МІНЯЄ нижче).
    далі_від_середини = відхил > 0.01
    напрям = ("нюд зміщує пропорцію далі від середини" if далі_від_середини
              else "нюд зміщує пропорцію до середини")
    зн = []
    for в in взуття:
        нюд = bool(в.get("нюд")) or (в.get("тон_до_шкіри") is True)
        if abs(відхил) <= 0.01:
            continue
        конфлікт = (відхил > 0.01 and нюд)
        # ── СУДЯТЬ ЦЮ ПАРУ, А НЕ ГІПОТЕТИЧНИЙ НЮД (08.09.2026) ─────────────────
        # ЩО ЦЕ МІНЯЄ (правило 3, before/after). `напрям` каже, що робить НЮД, і
        # нічого не каже про пару, яку зараз судять: нюдова й контрастна пари при
        # тій самій пропорції діставали ОДИН рядок і ОДНУ силу. Бік лежав у
        # `ремонт`, а він до моделі не доїжджає (`bridge._стислі_знахідки` лишає
        # правило, силу, суть і речі; `pipeline.промпт_ремонту` друкує саму суть).
        #   before (тіло з ВИМІРЯНИМ пахом 84 см на 168, спідниця міді):
        #     нюдова пара     · нога — 50.0% зросту; нюд зміщує пропорцію далі від середини [0.37]
        #     контрастна пара · нога — 50.0% зросту; нюд зміщує пропорцію далі від середини [0.37]
        #   after:
        #     нюдова пара     · нюд жене пропорцію далі від середини: нога 50.0% зросту,
        #                       пара «човники нюдові» — узяти контрастну пару [0.37]
        #     контрастна пара · контраст тримає пропорцію ближче до середини: нога 50.0%
        #                       зросту, пара «човники чорні» — нюд зсунув би її далі [0.37]
        # ЧОМУ СТАРИЙ РЯДОК НЕДІЄВИЙ: він описує гіпотетичний нюд, а не річ в образі,
        # тому на парі, яка вже й так робить потрібне, читається як докір, а на парі,
        # яку треба міняти, — як опис погоди.
        зн.append(dict(_зн("K-SHO-09", "soft" if конфлікт else "hint",
            "%s: нога %.1f%% зросту, пара «%s» — %s"
            % (("нюд жене пропорцію далі від середини" if нюд else
                "контраст тримає пропорцію ближче до середини") if далі_від_середини else
               ("нюд зводить пропорцію до середини" if нюд else
                "контраст лишає пропорцію далі від середини"),
               частка * 100, в.get("назва") or в.get("id"),
               ("узяти контрастну пару" if нюд else "нюд зсунув би її далі")
               if далі_від_середини else
               ("ця пара й працює на ціль" if нюд else
                "звести нюдом або тоном колготок")),
            [в.get("назва") or в.get("id")],
            "ціль двобічна: коли пропорція вже далі від середини, нюдова пара зміщує "
            "її ще далі — тобто дає протилежний результат тому, що дає при пропорції "
            "з іншого боку середини. Одностороннє «нюд завжди краще» заборонене",
            ремонт=(["контрастна пара: вона зміщує пропорцію торс : нога до середини"]
                    if конфлікт else ["нюд або тон колготок: зміщує пропорцію до середини"]),
            ламається="нейтральна точка 0.48 — [конвенція], середина того самого "
                      "шаблону, а не виміряна норма; і «нюд» у фіді не позначений — "
                      "береться з поля речі, якого український роздріб не несе",
            поріг=0.01, вимір=abs(відхил), повна=0.06),
            сила_нп=round(min(0.7, abs(відхил) / 0.06 * 0.5 + 0.2), 2),
            сила_нп_джерело="вимір (частка ноги − нейтральна точка)"))
        _СЛ.запис("K-SHO-09", "двобічна ціль: пропорція торс : нога", "подовження_ноги",
                  значення="частка %.3f" % частка, сила=0.4, напрям=напрям)
    return зн

