def маса_взуття(речі):
    """K-SHO-10. Масу взуття задає ВАГА ПОЛОТНА низу, а не сам лише його обʼєм.

    ЩО ЦЕ МІНЯЄ (before/after). before — «маса взуття ↔ обʼєм низу» бере на вхід
    силует крою, і твідове максі та віскозне максі дістають ОДИН список взуття.
    after — рід тканини стає другим входом (тема-3 його вже виводить із назви:
    на ager це 68 низів зі 127), і два однакові за кроєм максі дістають РІЗНІ
    списки: під важкий твід делікатна пара губиться, під віскозу — ні.

    ДЕ ЛАМАЄТЬСЯ, І ЦЕ НЕ ДРІБНИЦЯ: правило тягне В ПРОТИЛЕЖНИЙ БІК від K-SHO-07
    («низький виріз подовжує ногу»). Під важким максі низький виріз програє масі,
    під легким — виграє. Джерела цього конфлікту не розвʼязують, тому обидві
    знахідки виходять РАЗОМ і суперечність називається вголос, а не ховається
    вибором сторони.
    Ваги полотна — МОЯ шкала, не вимір: справжня вага в г/м² у фіді відсутня,
    а рід тканини — це слово з назви. Тому це впорядкування, ніколи не гейт.
    """
    зн = []
    низи = [р for р in речі if р.get("слот") in ("низ", "сукня", "комплект")]
    взуття = [р for р in речі if р.get("слот") == "взуття"]
    if not низи or не_порожньо(взуття) is False:
        return зн
    for н in низи:
        рід = (н.get("рід_тканини_слово") or н.get("текстура") or "").lower()
        вага = next((v for k, v in ТКАНИНА_ВАГА.items() if k in рід), None)
        if вага is None:
            continue
        for в in взуття:
            маса = МАСА_ВЗУТТЯ.get(в.get("тип"))
            if маса is None:
                continue
            розрив = вага - маса          # >0: полотно важче за взуття
            if розрив <= 0.3:
                continue
            зн.append(dict(_зн("K-SHO-10", "soft",
                "делікатне взуття під важким полотном (%s)" % рід,
                [в.get("назва") or в.get("id"), н.get("назва") or н.get("id")],
                "масу взуття задає ВАГА ПОЛОТНА низу, а не сам лише його обʼєм: під "
                "важким полотном (%s, умовна вага %.2f) пара умовної маси %.2f "
                "губиться — той самий крій із легкої тканини такої проблеми не має"
                % (рід, вага, маса),
                ремонт=["важча пара того ж інтервалу формальності",
                        "АБО той самий крій низу в легшій тканині"],
                ламається="правило тягне ПРОТИ K-SHO-07: під важким максі низький виріз "
                          "програє масі, під легким — виграє, і джерела цього не "
                          "розвʼязують. Ваги полотна — МОЯ шкала (справжньої ваги в "
                          "г/м² фід не несе, рід тканини — слово з назви), тому це "
                          "впорядкування, ніколи не гейт",
                поріг=0.3, вимір=розрив, повна=1.0),
                сила_нп=round(min(0.8, (розрив - 0.3) / 0.7 * 0.6 + 0.2), 2),
                сила_нп_джерело="вимір (вага полотна − маса пари, умовні одиниці)"))
            _СЛ.запис("K-SHO-10", "маса взуття проти ваги полотна", "маса_взуття",
                      значення="%.2f vs %.2f" % (вага, маса), сила=0.5,
                      напрям="другий вхід понад обʼєм крою")
    return зн


