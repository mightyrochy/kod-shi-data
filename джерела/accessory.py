def _рід_елемента(e):
    м = (e.get("метал") or "").lower()
    if м:
        return "метал «%s» біля обличчя" % м if (e.get("near") or 0) >= 0.3 else "метал «%s»" % м
    if e.get("візерунок"):
        return "джерело принта"
    if (e.get("блиск") or 0) >= 2:
        return "джерело блиску"
    if (e.get("near") or 0) >= 0.3:
        return "приобличчевий акцент"
    # ── РІД, ЯКИЙ ЖИВИЙ КАТАЛОГ СПРАВДІ ДАЄ (17.09.2026) ─────────────────────
    # Чотири роди вище стоять на полях, яких аксесуар у цьому фіді майже не має.
    # Виміряно прогоном образу з пʼятьма аксесуарами: рід «інше» ×5, дублів нема,
    # знахідки нема. Отже прохід на віднімання не міг спрацювати НІ РАЗУ:
    #   · `візерунок` і `блиск` на аксесуарах порожні;
    #   · `near` після перенормування дає 0.067 і сумці, і хустці — нижче за 0.3
    #     завжди;
    #   · `метал` того дня не писав НІХТО. ⚠ ЦЕ ЗМІНИЛОСЬ У ТОЙ САМИЙ ДЕНЬ: гілка
    #     K-CRA-07 під'єднала `feed.метал` до запису каталогу, і тепер метал несуть
    #     43 аксесуари з 973 у пакеті стенда (золото 16, сталь 15, срібло 12).
    #     Тобто перший рід ожив — але лише на ювелірній сорок третині, і для решти
    #     аксесуарів усе сказане лишається в силі.
    # `C` (хрома елемента) є в КОЖНОГО елемента — її ставить `outfit.гучність` на
    # кожному проході. Поріг не свій: `реєстр_правил.REGISTRY["hi_C"]` (40.0, K-COL-02
    # «високонасичений елемент»). І рід тут не за сімʼєю кольору, а спільний: два
    # гучні аксесуари витрачають ОДИН бюджет — саме це й каже K-ACC-01 («сережки —
    # приобличчевий колір і витрачають із бюджету хроми»).
    if (e.get("C") or 0) >= _РЕЄСТР.REGISTRY["hi_C"]["val"]:
        return "гучний колірний акцент"
    return "інше"


