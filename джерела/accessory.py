# ═════════════════ 8. ЦІНА ЗА КОМБІНАТОРНИМ ОБХВАТОМ (K-PRC-01/02) ═════════════════
def ціна_за_обхват(кандидати, каталог, слоти=("верх", "низ"), сумісні=None):
    """K-PRC-01. Вісь — не ціна, а ціна поділена на комбінаторний обхват.

    ЩО ЦЕ МІНЯЄ (before/after). before — ціна у фіді є, правила нема; якби воно
    зʼявилось наївно, воно ранжувало б за дешевизною й систематично гнало б людину до
    трендового низу. after — система рахує, В СКІЛЬКОХ ОБРАЗАХ із наявного каталогу ця
    річ може взяти участь, і ділить ціну на це число. Це ЄДИНА метрика теми, яку
    система обчислює краще за людину: людині доводиться вгадувати кількість носінь, а
    система їх перебирає.

    ДЕ ЛАМАЄТЬСЯ: обхват рахується по НАШОМУ каталогу, не по життю людини. Річ може
    мати нульовий обхват у нас і десять образів у неї в шафі. Тому число — НИЖНЯ ОЦІНКА,
    і подавати його як прогноз носінь заборонено: лише як порівняння двох кандидатів у
    ТОМУ САМОМУ пулі.

    І ДРУГА МЕЖА, ЯКА Є ОБЛАСТЮ ВИЗНАЧЕННЯ: метрика систематично карає ЗАЯВНИЙ ПРЕДМЕТ.
    Річ, куплена бути одним яскравим акцентом, за побудовою входить у мало образів — і
    метрика назве її поганою покупкою. Це не помилка метрики, це її межа:
    CPW МІРЯЄ БАЗУ, НЕ АКЦЕНТ.
    """
    сумісні = сумісні or (lambda a, b: True)
    інші = {с: [r for r in каталог if r.get("слот") == с] for с in слоти}
    вихід = []
    for к in кандидати:
        ціна = к.get("ціна") or к.get("price")
        сл = к.get("слот")
        партнери = [с for с in слоти if с != сл]
        обхват = 0
        for с in партнери:
            обхват += sum(1 for r in інші.get(с, []) if сумісні(к, r))
        # аксесуар карається за ціну СЛАБШЕ: аксесуари мають найвищу частоту використання
        # в гардеробі, тож система, яка ранжує за ціною однаково для всіх слотів,
        # помиляється систематично.
        аксесуарний = сл in ("сумка", "шарф", "прикраси", "пояс", "головний_убір",
                             "годинник", "окуляри", "взуття")
        # `_ід` — службовий ключ, яким викликач кладе число НАЗАД у рядок речі
        # (`bridge._цінність_пулу`). Без нього вихід функції лишався звітом про
        # метрику, який ніяк не повʼязаний із конкретною карткою: назва не ключ,
        # бо дві речі магазину законно звуться однаково.
        запис = dict(річ=к.get("назва") or к.get("id"), слот=сл, ціна=ціна,
                     обхват=обхват, аксесуарний=аксесуарний, _ід=к.get("id"))
        if ціна is not None and обхват > 0:
            запис["ціна_на_образ"] = round(float(ціна) / обхват, 2)
        else:
            запис["ціна_на_образ"] = None
            запис["чому_нема"] = ("ціни в картці нема" if ціна is None
                                  else "нульовий обхват у НАШОМУ каталозі — це не нуль у її шафі")
        if к.get("ремонтопридатна") is not None and сл == "взуття":
            # K-PRC-02: пара з прошивною конструкцією має довший знаменник; клеєна не має.
            запис["ремонтопридатна"] = bool(к["ремонтопридатна"])
            запис["k_prc_02"] = ("прошивна конструкція подовжує знаменник"
                                 if к["ремонтопридатна"] else
                                 "клеєна: перевзути не можна, знаменник коротший")
        вихід.append(запис)
    # ── САМОЗВІТ ДИСКРИМІНАЦІЇ (обовʼязковий, не діагностика) ────────────────
    # ВИМІРЯНО НА ЖИВОМУ ФІДІ 26.08.2026, І ВИМІР ЗМІНИВ ПРАВИЛО.
    # Перший прогін на ager з ПОБЛАЖЛИВИМ предикатом сумісності (ΔE ≥ 5, тобто
    # «майже все з майже всім») дав обхват 120–127 при 257 речах. Тобто ціна÷обхват
    # ≈ ціна÷123 — метрика ВИРОДИЛАСЬ у ціну, перефарбовану в іншу назву, і збіг
    # топ-10 із наївним сортуванням за ціною був 8 із 10.
    # Другий прогін — з РЕАЛЬНИМ фільтром (вікна слотів + смуга когерентності
    # 5 ≤ ΔE ≤ 45) — дав обхват 2–57, збіг топ-10 упав до 2 із 10, і зʼявилось
    # справжнє перевертання: штани за 449 грн ідуть 56-ми за ціною і 6-ми за
    # ціною/образ, бо стають у пару з 57 верхами.
    # ВИСНОВОК, ЯКИЙ ТЕПЕР У КОДІ: метрика придатна рівно настільки, наскільки
    # `сумісні` відбиває СПРАВЖНІЙ відбір композитора. Тому функція рахує розкид
    # власного виходу й КАЖЕ, коли він вироджений, замість мовчки віддати число.
    обхвати = [x["обхват"] for x in вихід]
    розкид = (max(обхвати) - min(обхвати)) if обхвати else 0
    середній = (sum(обхвати) / len(обхвати)) if обхвати else 0.0
    # нульовий обхват у ВСІХ — теж виродження (і найгірше: метрика не визначена, це чиста
    # ціна); доти `середній > 0` пропускав його як «не вироджене» (спіймано 28.08.2026,
    # зріз каталогу з одних суконь → обхват 0–0 → «несе інформацію понад ціну»)
    вироджена = bool(обхвати) and (середній <= 0 or (розкид / середній) < 0.25)
    дискр = dict(обхват_мін=min(обхвати) if обхвати else None,
                 обхват_макс=max(обхвати) if обхвати else None,
                 відносний_розкид=round(розкид / середній, 2) if середній else None,
                 вироджена=вироджена,
                 чому=("обхват майже сталий — ціна÷обхват це ЦІНА, перефарбована в "
                       "іншу назву. Причина майже завжди одна: предикат `сумісні` "
                       "поблажливіший за справжній відбір композитора. Подавати це "
                       "число як окрему вісь заборонено"
                       if вироджена else
                       "обхват розрізняє кандидатів — метрика несе інформацію понад ціну"))
    if вихід:
        _СЛ.запис("K-PRC-01", "ціна ділиться на комбінаторний обхват", "ціна_за_обхват",
                  значення="кандидатів %d, обхват %s–%s, вироджена=%s"
                           % (len(вихід), дискр["обхват_мін"], дискр["обхват_макс"], вироджена),
                  сила=None, напрям="нижня оцінка, не прогноз носінь")
    return dict(кандидати=вихід, дискримінація=дискр,
                область_визначення="CPW міряє БАЗУ, не АКЦЕНТ: річ, куплена бути одним "
                                   "яскравим акцентом, за побудовою входить у мало образів, "
                                   "і метрика назве її поганою покупкою — це її межа, не помилка",
                застереження="обхват рахується по НАШОМУ каталогу; число є НИЖНЬОЮ оцінкою, "
                             "і подавати його як прогноз носінь заборонено")


