    лишились, ворота_зн = ворота_розміру(t, речі)
    погодні = сезон_і_погода(речі, темп_c=темп_c, опади=опади, реагенти=реагенти)
    # ЗНАЙДЕНО НА РЕАЛЬНОМУ ВИВОДІ СТЕНДА, НЕ В ТЕСТІ. Перша версія клала ВСЕ, що
    # прийшло з `ворота_розміру`, у відро «ворота» — і тестувальниця бачила під
    # заголовком «відкидають ДО естетики» знахідку K-EYE-01 з силою «питання», яка
    # нічого не відкидає, бо міжзіницевої відстані ніхто не питав. Це той самий
    # дефект, що вже виправлявся в самому `ворота_розміру`: ВІДРО МУСИТЬ ВИЗНАЧАТИ
    # РЕГІСТР ЗНАХІДКИ, а не те, з якої функції вона прийшла. «Питання» — окреме
    # відро, бо це черга на вхід, а не відмова.
    # ДРУГИЙ ВИМІР ТОГО САМОГО ДЕФЕКТУ, ЗНАЙДЕНИЙ НА ВИВОДІ (11.09.2026, Н-P32).
    # Правило «відро визначає регістр» виконувалось тут лише НАПОЛОВИНУ: у ворота й
    # питання розкладались обидва джерела, а в преференції — САМЕ ЛИШЕ `погодні`
    # (рядок звався `решта_погодних`). Отже знахідка воріт розміру, яка не блокує й
    # не є питанням, не потрапляла НІКУДИ:
    #   устілка 28,0 см × стопа 245 мм → K-SHO-15 «припуск +35 мм» (soft)
    #   lug-to-lug 53 мм × зап'ястя 16 см → K-WCH-01 «ширший за стелю» (soft)
    #   before: ворота [] · питання [] · преференції []  — обидві знахідки зникали
    #   after:  ворота [] · питання [] · преференції [K-SHO-15, K-WCH-01]
    # Обидві — «репліка за стелею тіру», тобто рівно той регістр, який ВПОРЯДКОВУЄ,
    # а не відкидає; у лозі вони лишались, у видачі — ні. Правило, яке лишає слід і
    # не доходить до жінки, — це той самий «вимір без читача», який система ловить
    # у корпусі, тільки всередині себе.
    _усі_ворота = ворота_зн + погодні
    ворота = [з for з in _усі_ворота if з.get("блокує")]
    питання = [з for з in _усі_ворота if з.get("сила") == "питання"]
    решта_воріт = [з for з in _усі_ворота
                   if not з.get("блокує") and з.get("сила") != "питання"]
    преференції = (решта_воріт
                   + край_аксесуара(t, речі)
                   + халява_і_поділ(t, речі)
                   + кольє_проти_горловини(t, речі)
                   + видимість_краю(речі, темп_c=темп_c)
                   + лінія_ноги(речі, особа=особа)
                   + ширина_й_розмір(речі)
                   + взуття_і_поділ(t, речі)
                   + аксесуар_як_структура(речі)
                   + передумови_пояса(t, речі)
                   + масштаб_аксесуара(речі)
                   + асиметрія_інтересу(речі)
                   + панчішні(речі, темп_c=темп_c)
                   + маса_взуття(речі)
                   + подовження_ноги(t, речі)
                   + вартість_носіння(речі, тривалість_год=тривалість_год, поверхня=поверхня)
                   + цінність_речей(речі))
    # ── K-ACC-07 / K-EYE-03: НОСІЙ ПРИОБЛИЧЧЕВОГО ПОЛЯ ЗВІЛЬНЯЄ ВЕРХ ─────────
    # Носій шукається в ЦЬОМУ СТАНІ образу: під застібнутим пальтом шарфа не видно,
    # і правило мовчить (умова теми-10, яка стала обчислюваною лише з темою-11).
    _місця_зн = місце_не_обране(речі)
    носій = носій_приобличчевого_поля(речі)
    запити_після, рятунок = (list(запити or []), [])
    if носій is not None and спец is not None and запити:
        запити_після, рятунок = рятівник_приобличчя(спец, запити, носій=носій)
    elif носій is not None:
        _СЛ.запис("K-ACC-07", "носій є, вікон для звільнення не передано",
                  "перевірити", значення="спец/запити відсутні", сила=0.0,
                  напрям="черга на вхід")
        рятунок = [dict(_зн("K-ACC-07", "питання",
            "носій приобличчевого поля є, але вікон для звільнення не передано",
            [носій.get("назва") or носій.get("id") or носій.get("слот")],
            "правило розширює пул верхів лише тоді, коли має ЩО розширювати: "
            "специфікацію палітри й запити у фід. Без них воно не має права ані "
            "спрацювати, ані вдавати, що спрацювало",
            ремонт="передати `спец` і `запити` у `accessory.перевірити`",
            ламається="це черга на вхід, а не провал: механізм працює, входу нема"),
            сила_нп=0.0, сила_нп_джерело="входу нема (спец/запити)")]
    # ── ПРАВИЛО, ЯКЕ ЄДИНЕ РОЗШИРЮЄ КАТАЛОГ, ЧЕКАЄ НА ОДНЕ РІШЕННЯ ───────────
    # Коли носія нема, але в образі СТОЇТЬ річ, яка ним стала б (хустка з
    # приобличчевим місцем серед допустимих, місце не обране), мовчання тут —
    # це «без входу», видане за «пройдено». Блокер названо: `feed.слоти` лишає
    # `місце=None` навмисно, бо його ставить композитор, а композитор його не
    # ставить. Ціна названа в самій знахідці: це ЄДИНЕ правило теми, яке пул
    # РОЗШИРЮЄ, і поки місце не обране, розширення не відбувається.
    if носій is None:
        for _р in речі:
            if _р.get("слот") != "шарф" or _р.get("місце"):
                continue
            _м = [м for м in (_р.get("місця") or ()) if м in ("шия", "волосся", "плечі")]
            if not _м:
                continue
            _ім = (_р.get("назва") or _р.get("id") or "хустка")[:40]
            рятунок.append(dict(_зн("K-ACC-07", "питання",
                "«%s» могла б зайняти приобличчеве поле, але місце не обране" % _ім, [_ім],
                "хустка на шиї, у волоссі чи на плечах НЕСЕ приобличчевий колір замість "
                "верху — і тоді верх оцінюється дальнім вікном, тобто пул верхів РОЗШИРЮЄТЬСЯ. "
                "Це єдине правило теми-10, яке каталог розширює, а не звужує. Допустимі "
                "приобличчеві місця цієї речі: %s; решта її місць (талія, ручка сумки, "
                "зап'ясток) приобличчевого поля не займають, тому вибір тут вирішує все"
                % ", ".join(_м),
                ремонт="композитор обирає місце зі списку `місця`, який `feed.слоти` вже "
                       "рахує й кладе в рядок каталогу",
                ламається="`місце` лишається None НАВМИСНО (`feed.слоти`): його ставить "
                          "композитор, і мовчазний дефолт «шия» тут уже був і був знятий "
                          "26.08.2026 — він звільняв колірне вікно верху на підставі "
                          "рішення, якого ніхто не ухвалював. Отже це не діра коду, а "
                          "названий розрив контракту: рішення нема кому ухвалити"),
                сила_нп=0.0, сила_нп_джерело="входу нема (місце хустки не обране)"))
            _СЛ.запис("K-ACC-07", "кандидат у носії є, місце не обране", "перевірити",
                      значення=_ім, сила=0.0, напрям="черга, не тиша")
            break
    преференції = регістр_оправи(преференції + [з for з in рятунок
                                                if з.get("сила") != "питання"])
    питання = питання + [з for з in рятунок if з.get("сила") == "питання"] + _місця_зн
    return dict(
        носій_приобличчевого_поля=(носій.get("назва") or носій.get("id")) if носій else None,
        запити_після=запити_після,
        лишились=лишились,
        ворота=ворота,
        питання=питання,
        преференції=[з for з in преференції if з.get("сила") != "питання"]
                    + [],
        без_відповіді=[з for з in преференції if з.get("сила") == "питання"] + питання,
        канал_3=команди_розкладки(речі, гардероб=гардероб),
        без_входу=без_входу(речі),
        # Тристановість дев'яти правил теми-10 — рядком, який читає
        # `суд_образу.чеклісти` (ЧЕКЛІСТ_АКСЕСУАРІВ). Без нього «вимкнено бо нема
        # входу» й «перевірено, чисто» виглядають з виходу однаково.
        входи_чекліста=входи_чекліста(речі, тривалість_год=тривалість_год),
        відра="ворота ВІДКИДАЮТЬ (блокує=True) · преференції ВПОРЯДКОВУЮТЬ · "
              "питання/без_входу — ЧЕРГА НА ВХІД, вони не роблять ні того, ні того. "
              "Відро визначає РЕГІСТР знахідки, а не функція, з якої вона прийшла",
        порядок="сезон/температура (K-WEA-04/07) → розмір (K-SIZ-01, K-SHO-13) → "
                "матеріал×погода (K-WEA-05) → підошва (K-WEA-06) ─── ворота ─── "
                "виріз · халява · маса · колір ─── преференції ─── "
                "вартість носіння за сценарієм (K-END-01, K-SHO-16). "
                "Перші чотири ворота відсікають більше, ніж усі преференції разом")
