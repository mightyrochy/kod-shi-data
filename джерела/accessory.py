def передумови_пояса(t, речі):
    """K-ACC-02. У пояса є ПЕРЕДУМОВА, а не лише параметр.

    ЧОГО ТУТ НЕ БУЛО. ID стояв рівно в одному місці — рядком таблиці
    `МІСЦЕ_НАСЛІДКИ` («талія»: «пояс — діють передумови пояса», K-ACC-02), тобто
    в ОПЦІЇ третього каналу. Опція називала правило й не виконувала його: пояс
    пропонувався «третьою річчю» будь-кому.

    ДВІ ВИМІРЯНІ ВЕЛИЧИНИ, ЯКИХ ВИМАГАЄ КОРПУС, І ЧЕСНИЙ СТАН КОЖНОЇ:
      · ВИРАЖЕНІСТЬ ТАЛІЇ — є й порахована: `fit.зони(t)["вектор"]["талія_виражена"]`
        (WHR ≤ 0.78, константа `fit.РЕЄСТР["whr_виражена"]`, T3, з того самого
        корпусу, що й правило);
      · ДОВЖИНА КОРПУСУ — вимірна, і НОРМИ ДЛЯ НЕЇ В КОРПУСІ НЕМА. `fit` каже це
        прямо про сусідню вісь: «норми, відносно якої тіло звалося б довгоногим чи
        довгокорпусним, у корпусі нема (тема-1 §12)». Тому число друкується як
        вимір і НЕ стає вердиктом — інакше правило вигадало б поріг, якого джерело
        не дає.

    Сила `soft`, і це не обережність: корпус сам пише «"easier / harder" is an
    ordering, not a prohibition… must yield to the person's stated wish».
    """
    пояси = [р for р in речі if р.get("слот") == "пояс"]
    if not пояси or not t or not t.get("обхвати"):
        return []
    try:
        вект = ПС.зони(t)["вектор"]
    except Exception:
        return []
    висоти = t.get("висоти") or {}
    корпус_см = ((висоти.get("плечі") or 0) - (висоти.get("талія") or 0)) or None
    частка = (корпус_см / float(t["зріст"])) if корпус_см and t.get("зріст") else None
    назви = sorted({(р.get("назва") or р.get("id") or "пояс")[:40] for р in пояси})
    if вект.get("талія_виражена"):
        _СЛ.запис("K-ACC-02", "передумова пояса виконана (талія виражена)",
                  "передумови_пояса", значення="WHR %.3f" % вект["WHR"], сила=None,
                  напрям="пройдено — це ВИКОНАНЕ правило, не мовчання")
        return []
    return [dict(_зн("K-ACC-02", "soft",
        "пояс тут не перша третя річ: талія не виражена (WHR %.2f при межі %.2f)"
        % (вект["WHR"], ПС.C["whr_виражена"]), назви,
        "перед шириною й посадкою пояса перевіряються ДВІ величини — виразність талії "
        "й довжина корпусу. Талія цієї людини не виражена, отже поясу нема за що "
        "триматись, і третю річ дешевше взяти з іншого слота. Довжина корпусу тут "
        "%s — це ВИМІР без вердикту: норми, відносно якої корпус звався б довгим чи "
        "коротким, у корпусі нема (тема-1 §12), і вигадувати її правило не має права"
        % ("%.0f см, тобто %.2f зросту" % (корпус_см, частка) if частка else "не порахована"),
        ремонт=["третя річ з іншого слота: хустка, верхній шар, прикраса",
                "якщо пояс лишається — ширший і на природній талії, не на стегнах: "
                "пояс на стегнах коротшає ноги й розширює середину"],
        ламається="«легше / важче» — це ПОРЯДОК, не заборона: корпус прямо каже, що це "
                  "`soft`-преференція й вона мусить поступитись висловленому бажанню "
                  "людини. І перевірена тут ОДНА з двох величин: другу (довжину корпусу) "
                  "нема з чим порівняти",
        поріг=ПС.C["whr_виражена"], вимір=вект["WHR"], повна=1.0),
        сила_нп=round(min(0.5, 0.2 + (вект["WHR"] - ПС.C["whr_виражена"]) * 2.0), 2),
        сила_нп_джерело="вимір (WHR проти fit.whr_виражена)")]


