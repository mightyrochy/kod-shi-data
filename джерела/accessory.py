    ПРИОБЛИЧЧЯ = ("шия", "волосся", "плечі")

    def _займає(р):
        м = р.get("місце")
        if м in ПРИОБЛИЧЧЯ:
            return True
        місця = tuple(р.get("місця") or ())
        return bool(місця) and all(x in ПРИОБЛИЧЧЯ for x in місця)

    закрито = any(р.get("слот") == "верхній_шар" and р.get("стан") == "застібнуто"
                  for р in речі)
    for р in речі:
        if р.get("слот") == "шарф" and _займає(р):
            if закрито and р.get("поверх_шару") is not True:
                continue
            if р.get("поверх_шару") is False:
                continue
            return р
    for р in речі:
        if р.get("слот") == "окуляри":
            return р
    return None


