                ("виріз низький: пара «%s» лишає лінію ноги від пальців — тримати пару"
                 if низький else
                 "виріз високий: пара «%s» ріже лінію ноги посеред стопи — узяти "
                 "нижчий виріз у тому ж інтервалі формальності") % назва, [назва],
