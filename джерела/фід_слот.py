# розбирати назву крамниці на частини («це комплект? з яких частин? де верх, де низ?»)
# згодом буде вона, не словник тут. Тому слова сюди не додаються, навіть коли вимір
# показує пропуск. Пропуски, які цей словник дає, не приховані: повний перелік із сирою й судовою назвою кожної речі є вхідним
# набором для завдання мовній моделі («Двійка класичні бермуди + жилетка приталена»
# — 9 речей feelyou, де «бермуд» не впізнано низом; «Комплект туніка та штани» —
# 1 річ maxa; «Трійка піджак + жилетка + прямі пломбір» — еліпсис «прямі»).
# «баск» тут не стоїть: баска — деталь («Брюки з баскою»), а не окрема річ.
# «джинси» — іменник-низ лише у формах «джинси/джинсів/…»; «джинс» (матеріал) і «джинсовий» (ознака) низом не є.
ВЕРХ_СЛОВО = __import__("re").compile(r"топ|жакет|блуз|сорочк|піджак|кардиган|жилет|светр|кофт|майк|футболк|боді|корсет|кейп")
НИЗ_СЛОВО = __import__("re").compile(r"штан|брюк|спідниц|шорт|бермуд|палацц|кюлот|легінс|леггінс|джинс(?:и|ів|ам|ами|ах)\b")
_СПОЛУЧНИК_ПАРИ = frozenset(("+", "і", "й", "та", "з", "зі", "із"))


def _пара_верх_низ(т, зв_язок=True):
    """Чи названі ДВІ окремі речі: слово-верх і слово-низ як іменники (початок слова,
    головний іменник складеного — до дефіса), а між ними — «+», «і/й/та» чи «з/зі/із».
    Підрядок усередині слова («каштани», «Каштани» ≠ «штани»), ознака («джинсовий топ»)
    і складений іменник («сукня-сорочка») пари не дають. Коли назва вже має слово
    «комплект/набір/…» (`зв_язок=False`), сполучник не потрібен: частини йдуть переліком."""
    слова = re.findall(r"\+|[\w'’]+(?:-[\w'’]+)*", т)
    верх = [i for i, с in enumerate(слова) if ВЕРХ_СЛОВО.match(с.split("-")[0])]
    низ = [i for i, с in enumerate(слова) if НИЗ_СЛОВО.match(с.split("-")[0])]
    return any(not зв_язок or _сполучник_між(слова, a, b) for a in верх for b in низ)


def _сполучник_між(слова, a, b):
    ліво, право = sorted((a, b))
    return any(с in _СПОЛУЧНИК_ПАРИ for с in слова[ліво + 1:право])


ДІЛОВИЙ = __import__("re").compile(r"брючн|ділов|жакет|піджак|блейзер|класичн|офіс|двійк|трійк")
ПОВСЯКДЕННИЙ = __import__("re").compile(r"кардиган|бомбер|худі|світшот|трикотаж|спорт|футер|велюр|фліс|шорт|кімоно|піжам|домашн|футболк|майк|лляк|льон|лляна|муслін")


def _тип_набору_зі_слів(offer):
    """Тип цілого комплекту за словами частин: «костюм» (діловий, 7–9),
    «костюм_повсякденний» (3–5) або «комплект» (без підказки — широкий інтервал).

    ── КОЛИ НАЗВИ ФІДУ НЕМА, ВІДПОВІДАЄ РОЗДІЛ КРАМНИЦІ ────────────────────
    ЩО ЦЕ МІНЯЄ В РІШЕННІ. Відколи `набір_цілий` читає назву СУДУ, комплектами
    стають і 46 речей із СКЛАДЕНОЮ назвою («МОДЕЛЬ №871 СВІТЛИЙ БЕЖ» → на картці
    «Костюм бежевий»). Тип їм рахує вже не `тип_речі` (він читає категорію), а ця
    функція — а вона читала ЛИШЕ назву, і назва в них не каже нічого: увесь розбір
    ділового проти повсякденного мовчав, і річ діставала широкий інтервал «комплект»
    (3–7) там, де до правки мала (7–9). Тобто моя ж правка звузила б вхід іншому шару.
    Дорога та сама, що вже стоїть у `_слот_за_типом` і в дорозі фактів `набір_цілий`:
    коли назва нічого не значить, відповідає `категорія_магазину`. У stolyarchuk вона
    відповідає дослівно — «КАТАЛОГ > КЛАСИЧНІ КОСТЮМИ > …» проти «КАТАЛОГ > СПОРТИВНІ
    КОСТЮМИ > …», і друге ВИПРАВЛЯЄ старий вердикт: спортивний костюм мав тип «костюм»
    (7–9, діловий) і йшов у весільні нагоди так само, як двійка з вовни.
    ВОРОТА ВУЗЬКІ НАВМИСНО — дві умови разом: назва не дала підказки І назви фіду нема
    (`назва_суду` не дорівнює сирій, тобто вона складена або з опису). Речі, чию назву
    фід дав, судяться назвою, як доти; ширший варіант (питати розділ у КОЖНОГО набору)
    зачіпає помітно більше речей і має знахідки в обидва боки — це окремий рядок дошки
    з власним виміром, не доважок до цього.
    РОЗДІЛ КРАМНИЦІ — НЕ НОВЕ СЛОВО: `_ДІЛОВИЙ` і `_ПОВСЯКДЕННИЙ` лишаються ті самі,
    міняється лише РЯДОК, до якого їх прикладають, коли назви фіду нема. Тією самою
    дорогою вже ходить `_слот_за_типом` («%s %s» % (тип, категорія_магазину)).
    ВИМІР на каталог_повний, ДО = origin/main в окремому робочому дереві. Типи ВСІХ
    комплектів: ДО (345) костюм 116 · повсякденний 87 · комплект 142;
    ПІСЛЯ (391) костюм 152 · повсякденний 104 · комплект 135."""
    сира = f"{offer.get('назва','')}".lower()
    т = re_тип.sub(" ", сира)
    if ДІЛОВИЙ.search(т) and not ПОВСЯКДЕННИЙ.search(т):
        return "костюм"
    if ПОВСЯКДЕННИЙ.search(т):
        return "костюм_повсякденний"
    if назва_суду(offer).lower() != сира:
        р = re_тип.sub(" ", ((offer.get("параметри") or {}).get("категорія_магазину") or "").lower())
        if ДІЛОВИЙ.search(р) and not ПОВСЯКДЕННИЙ.search(р):
            return "костюм"
        if ПОВСЯКДЕННИЙ.search(р):
            return "костюм_повсякденний"
    return "комплект"


# Слова-набори у полі `параметри.тип` — те саме, що `_НАБІР` шукає в назві, але
# сказане фідом як ФАКТ. Потрібні, коли назви нема: див. `набір_цілий`.
_ТИПИ_НАБОРУ = frozenset(("костюм", "комплект", "двійка", "трійка", "набір"))


def _набір_зі_слів(offer):
    """True — SKU є цілим образом (верх+низ). None — не набір. False — набір, але
    не цілий (дві речі одного слота), і він лишається у своєму слоті.

    НАЗВА-РЕЧЕННЯ НЕ КАЖЕ ПРО НАБІР. «Базові кольори
    пасують під все: від куртки до пуховика» — це спортивний КОСТЮМ stolyarchuk,
    і жодне слово назви цього не каже, бо назва — перше речення реклами. Фід
    каже: `тип=костюм`, `категорія_магазину=… СПОРТИВНІ КОСТЮМИ …`. Виміряно на
    каталог_повний: 104 речі з назвою-реченням мають набірний `тип`, і 67 із них
    ловила назва («Костюм: жилет вільного крою…»), а 37 не ловило ніщо — вони
    лежали половинами у «верх» (67), «низ» (25), «верхній_шар» (10) і «сукня» (2),
    і композитор законно додавав до костюма ще спідницю.

    ── А НАЗВА-АРТИКУЛ НЕ КАЖЕ ПРО НЬОГО ТИМ ПАЧЕ ──────────────────────────
    ЩО ЦЕ МІНЯЄ В РІШЕННІ. `назва_суду` задає контракт: «Назва, якою КЛАСИФІКУЄТЬСЯ
    річ, — та сама, що на картці. ЗАВЖДИ» (`назва_суду`). Ця функція лишилась на
    СИРІЙ назві фіду, тому артикул замість назви лишає помилку: `ж-02299@stolyarchuk.com.ua` лежить у фіді як «МОДЕЛЬ №876 ХАКІ» —
    артикул, який предмета не називає взагалі, — при `тип=костюм` і розділі
    крамниці «Костюми». Суд назви його забракував, `чистка_каталогу` склала для
    картки «Костюм хакі», жінка бачила саме це слово — а `набір_цілий` шукала
    «костюм» у «модель №876 хакі», не знаходила й віддавала None. Слот лишався
    «верх», і рука 1 ставила ЦІЛИЙ костюм зі своїми штанами в один образ зі
    спідницею жінки з фото: подвійний низ, який тестувальниця й побачила на картці 3.
    Дорога фактів (`параметри.тип`) стояла поруч і не бралась: її ворота — поле
    `назва_джерело == "опис"`, а тут назва не з опису, вона просто нічого не значить.
    ТЕПЕР назва СУДУ — ДРУГИЙ свідок: сира питається першою (рівно як доти), і лише
    коли вона про набір мовчить, питається та, що на картці (`слот` → `_рід_речі` →
    `назва_суду`). Порядок саме такий, бо заміна одного свідка другим губила речі, де
    набір називає сира: `ж-08427@sarahberlin.com` «Мереживний комплект: боді корсет …
    та довга спідниця» став би «верхом» із типом «спідниця» (повернення тестувальниці
    №2). Два свідки — і жодна річ main вердикту не втрачає.
    МЕЖА ТА САМА, ЩО В ДОРОЗІ ФАКТІВ: коли в СИРІЙ назві стоїть ПРИКМЕТНИК
    «костюмн…», другий свідок замикається — «Брюки завужені костюмна тканина шавлія»
    (vovk) лишається штанами, як і доти.
    ВИМІР на каталог_повний (11 828 речей у каталозі), ДО = origin/main, окреме робоче
    дерево: комплектів 345 → 391, усі у слоті «комплект»; ДОДАНО 46, ЗНЯТО 0.
    Усі 46 — самим цим рядком: 45 зі складеною назвою, 1 з назвою з опису. Нових слів
    у словниках частин при цьому НЕ додано (слово власника: мовні костилі в коді
    заморожено, розбір назви на частини — робота мовної моделі); речі, яких словник і
    далі не ловить, треба передавати мовній моделі із сирою й судовою назвою кожної."""
    сира = f"{offer.get('назва','')}".lower()
    п = offer.get("параметри") or {}
    if (п.get("назва_джерело") or "").strip().lower() == "опис":
        # НАЗВА-РЕЧЕННЯ НЕ КАЖЕ ПРО НАБІР НІ «ТАК», НІ «НІ», і читати її тут узагалі
        # не можна. Спіймано на аркуші cooshwear: мереживне БОДІ (`тип=боді`, url
        # /jane-lace-bodysuit-…/) лежало у слоті «комплект» — і лежало там і на
        # головній гілці, — бо рекламна фраза закінчується словом «…чи об'ємний
        # КОСТЮМ». Тут вирішує той самий факт, що й у `_рід_речі`: `параметри.тип`.
        # МЕЖА ФАКТУ — `_re_тип.search` НА СИРІЙ НАЗВІ: «Ці штани на резинці з
        # КОСТЮМНОЇ тканини» (vovk, url /brjuki-na-rezinci-kostjumna-tkanina-chorni/)
        # має `тип=костюм`, бо в полі осів ПРИКМЕТНИК. Поле — одне слово, і
        # відрізнити в ньому «костюм» від «костюмної тканини» нічим; відрізняє назва,
        # у якій прикметник лишився цілим. Без цієї межі 12 пар штанів vovk їхали б
        # у «комплект».
        if ((п.get("тип") or "").strip().lower() in _ТИПИ_НАБОРУ
                and not re_тип.search(сира)):
            return True
        return None
    # ── ДВА СВІДКИ, А НЕ ОДИН ──────────────────────────────────────────────
    # Перша спроба цього рядка ЗАМІНИЛА сиру назву судовою — і тим загубила речі,
    # де набір називає саме СИРА: `ж-08427@sarahberlin.com` «Мереживний комплект:
    # боді корсет … та довга спідниця» на main був комплектом, а став «верхом» із
    # типом «спідниця», бо в складеній назві картки слова «комплект» нема.
    # Тому порядок такий: СПЕРШУ сира, щоб не змінити її чинні вердикти,
    # і лише коли вона про набір МОВЧИТЬ, питається судова. Межа
    # прикметника лишається на сирій: «костюмн…» у ній замикає другого свідка, бо
    # саме через нього в поле `тип` потрапляє «костюм» від тканини, а не від речі.
    т = re_тип.sub(" ", сира)
    if not НАБІР.search(т):
        суду = назва_суду(offer).lower()
        if суду != сира and not re_тип.search(сира):
            т = re_тип.sub(" ", суду)
        if not НАБІР.search(т):
            # Дві названі частини різних слотів — теж цілий набір, але лише коли
            # назва явно з'єднує їх, а не просто згадує сусідню річ.
            return True if _пара_верх_низ(т) else None
    # Набірний іменник на початку називає SKU як ціле; далі це може бути
    # перелік частин, зокрема сукня з кардиганом або туніка зі штанами.
    # «Набір» без частин різних слотів («набір із чорного та молочного топа») — дві
    # речі одного слота, не цілий образ: голова вирішує для решти набірних іменників.
    голова = " ".join(т.split()[:3])
    if re.search(r"\b(?:костюм|комплект|двійк\w*|трійк\w*|сет)\b", голова):
        return True
    return _пара_верх_низ(т, зв_язок=False)


