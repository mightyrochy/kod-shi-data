СЛОВА_ДВОСЛОТОВИХ = {сл: пара for пара, слова in ДВОСЛОТОВІ for сл in слова}


def слоти(offer):
    """K-ACC-12. Множина допустимих місць речі. Порожня множина неможлива: якщо річ
    не багатомісна, множина — це її єдиний слот.

    Повертає dict(слот=..., місця=(...), місце=None, чому=...). `місце` лишається
    None НАВМИСНО: його ставить композитор, і поки він цього не зробив, жодне правило
    місця застосовувати не можна. Мовчазний дефолт «шия» повернув би стару помилку
    під новим імʼям.

    ДЕ `місце` ВСЕ Ж ЗʼЯВЛЯЄТЬСЯ. Тут — лише для одномісної речі
    («слот і місце збігаються»). Для сумки його виводить `фід_атрибути.спосіб_
    носіння` зі слова САМОЇ картки, і кладе `фід_каталог` у рядок каталогу тим
    самим шляхом, що `слоти_альт` і `місця`. Ця функція того виводу не робить
    навмисно: `фід_атрибути` імпортує `фід_слот`, і зворотний імпорт замкнув би
    коло. Крок, який зводить обидва джерела в одне поле речі, — один і названий:
    `composer.обрати_місце`."""
    запис = offer.get("запис_речі") or offer
    if "місця" in запис:
        if слот(offer) is None:
            return dict(слот=None, місця=(), місце=None, слоти_альт=(), чому="річ поза каналом каталогу")
        return {к: запис.get(к) for к in ("слот", "місця", "місце", "слоти_альт", "розмір_см", "чому")}
    с = слот(offer)
    if с is None:
        return dict(слот=None, місця=(), місце=None, слоти_альт=(),
                    чому="категорія не лягла в жоден слот")
    альт = альтернативні_слоти(offer, с)
    if с not in БАГАТОМІСНІ:
        return dict(слот=с, місця=(с,), місце=с, слоти_альт=альт,
                    чому="річ одномісна: слот і місце збігаються"
                         + ("; слот, однак, двозначний — вибір за композитором" if альт else ""))
    місця, чому = БАГАТОМІСНІ[с]
    if с == "шарф":
        # ── КОНСТРУКЦІЯ РЕЧІ ЗВУЖУЄ МНОЖИНУ РАНІШЕ ЗА ФОРМАТ ───────────────────
        # Коментар до `БАГАТОМІСНІ` вище сам це й декларує: «багатомісність —
        # властивість КОНКРЕТНОЇ речі», і саме тому з таблиці свого часу прибрали
        # прикраси (каблучка може бути лише на пальці). Те саме стосується
        # замкненого шарфа: снуд, хомут і шарф-краватка НЕ лягають ні на талію, ні
        # на ручку сумки, ні на зап'ясток — це не наша обережність, це їхня форма.
        # ЧОМУ ЦЕ ВАЖИТЬ БІЛЬШЕ ЗА ТРИ КАРТКИ: коли ВСІ допустимі місця речі
        # приобличчеві, місце можна не обирати — річ займає приобличчеве поле в
        # будь-якому разі, і K-ACC-07 перестає чекати на рішення композитора.
        # ВИМІРЯНО на `каталог_повний.xml` (93 шарфи): снуд/хомут 1, шарф-краватка
        # 2 — разом 3 (3.2 %). Число мале й чесне; воно не міняється від того, що
        # ми його назвали.
        сирий = "запис_речі" in offer or not ("тип" in offer or "слот" in offer)
        _т = ("%s %s" % (назва_суду(offer), offer.get("категорія") or "")).lower() if сирий else ""
        if any(k in _т for k in ("снуд", "хомут", "шарф-краватк", "шарф краватк")):
            return dict(слот=с, місця=("шия", "волосся"), місце=None,
                        розмір_см=розмір_квадрата(offer), слоти_альт=альт,
                        чому=чому + "; замкнена конструкція (снуд/хомут/краватка) "
                                    "лишає лише приобличчеві місця")
        # ФОРМАТ ГЕЙТИТЬ МІСЦЕ (K-CRA-12), і ворота ФІЗИЧНІ: квадрата 70 см не
        # вистачає на повне обгортання голови, а 90 — вистачає. Це єдина частина
        # хусткового шару, що не є конвенцією.
        р = розмір_квадрата(offer) if сирий else offer.get("розмір_см")
        if р is not None and р < 90:
            місця = tuple(m for m in місця if m not in ("волосся", "верх", "плечі"))
            чому += "; формат %d см відсікає повне обгортання, плечі й «як верх»" % р
        return dict(слот=с, місця=місця, місце=None, розмір_см=р,
                    слоти_альт=альт, чому=чому)
    return dict(слот=с, місця=місця, місце=None, слоти_альт=альт, чому=чому)


def альтернативні_слоти(offer, основний):
    """Дозволені слоти виду з таблиці кодів, без повторного читання назви."""
    запис = offer.get("запис_речі") or offer
    if "слоти_альт" in запис:
        return tuple(с for с in запис["слоти_альт"] if с != основний)
    тип = запис.get("тип") if "тип" in запис else вид_речі(offer)[0]
    коди = _СЛ.ДВОСЛОТОВІ_ТИПИ.get(_код_типу(тип), ())
    return tuple(_СЛ.КЛЮЧІ[с] for с in коди if _СЛ.КЛЮЧІ[с] != основний)


РОЗМІР_РЕ = __import__("re").compile(r"(\d{2,3})\s*[хx×*]\s*(\d{2,3})")
def розмір_квадрата(offer):
    """Сторона квадрата зі назви/опису («90х90», «70x70»). None — не названо.
    Український роздріб дає це регулярно: 90×90 — стандартний лістинг."""
    т = f"{offer.get('назва','')} {offer.get('опис','') or ''}"
    м = РОЗМІР_РЕ.search(т)
    if not м:
        return None
    a, b = int(м.group(1)), int(м.group(2))
    return min(a, b) if abs(a - b) <= max(a, b) * 0.25 else None

