# ПОЛЕ, А НЕ ВИКЛИК: рахує відновлену назву `чистка_каталогу` раз на каталог
# (`назва_речі.відновлена_назва`, 6.45 с), кладе в оффер, і сюди вона приходить
# готовою. Імпортувати `назва_речі` тут не можна й не треба: він сам імпортує
# `фід_слот` (`СЛОТ_КЛЮЧІ`), і це було б коло.
# Речі рук 3–4, фікстури й будь-який оффер без поля судяться сирою назвою, як досі.
def назва_для_людини(offer):
    """Назва, яку БАЧИТЬ жінка: та, що на картці, хоч би звідки вона взялась.

    Нею шукається її бажання, нею річ зветься в пулі для моделі й у рядку «за
    бажанням додано в пул». Рекламне речення фіду, яке суд назви відкинув, сюди
    не потрапляє — саме через нього бажання «практичний» знаходило комбінезон
    за словом «…додають виробу практичності» — рекламним текстом, а не назвою речі."""
    o = offer or {}
    return str(o.get("назва_показу") or o.get("назва") or "")


