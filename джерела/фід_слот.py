# Тип — не дрібниця показу: він діє у веті за типом, у пошуку за бажанням
# (`різноманітність_пулу.слот_бажання` → слот + тип), у траурному регістрі й у
# суді дрес-коду. Бажання «джинси» приводило в пул джинсову СПІДНИЦЮ.
_ТИПИ_РОДОВІ = ("сумка_без_уточнення", "шарф_без_уточнення", "прикраса_без_уточнення")
# Два ключі словника, що називають і РІЧ, і ТКАНИНУ. Саме через них тип і
# з'їжджав: «джинсова спідниця» — спідниця з деніму, а не джинси.
_ТИПИ_ТКАНИНИ = ("джинси", "трикотаж")
_ТИПИ_ВЗУТТЯ = ("ботфорти", "челсі", "уггі", "балетки", "мюлі", "еспадрильї", "човники",
                "туфлі", "мокасини", "лофери", "кросівки", "кеди", "черевики", "чоботи",
                "босоніжки", "сандалі")
# ГОЛОВА, ЩО ПОСТУПАЄТЬСЯ ФОРМІ В ОДНОМУ СЛОВІ. Звичайно перемагає ІМЕННИК-голова
# («Спідниця-шорти» — спідниця, «Пальто-піджак» — пальто, «Блейзер-куртка» —
# блейзер), бо в українському складеному іменнику річчю є ПЕРШИЙ елемент.
# Виняток один: голова сама є РОДОВИМ словом («родину знаємо, форми не знаємо»),
# а хвіст називає ФОРМУ ТІЄЇ САМОЇ родини. Тоді хвіст точніший:
#   «Туфлі-човники» (23 у каталозі) → човники, «Сумка-шопер» (6) → шопер,
#   «Сукня-футляр» → футляр.
# «Тієї самої» — не формальність: «Сукня-сорочка» лишається сукнею, бо «сорочка»
# — форма ВЕРХУ, а не сукні, і взяти її означало б судити сукню формальністю
# сорочки. Саме це розрізнення й робить `_ФОРМИ_РОДИНИ` списком, а не прапорцем.
_ФОРМИ_РОДИНИ = {
    "сукня_без_уточнення":    ("вечірня_сукня", "коктейльна_сукня", "футляр", "сарафан"),
    "сумка_без_уточнення":    ТИПИ_СУМОК,
    "шарф_без_уточнення":     ТИПИ_СЛОТА["шарф"],
    "прикраса_без_уточнення": ТИПИ_СЛОТА["прикраси"] + ТИПИ_СЛОТА["каблучка"],
    "туфлі":                  _ТИПИ_ВЗУТТЯ,
}
# «сукня_без_уточнення» нема у `ТИП_КЛЮЧІ` — вона стоїть окремим запасним рядком
# у `_тип_речі_обчислити`. Щоб голова змагалась за позицією нарівні з рештою,
# ключі сукні додаються в кінець пошуку: при рівній позиції форма виграє.
_КЛЮЧІ_ТИПУ_З_СУКНЕЮ = list(ТИП_КЛЮЧІ) + [("сукня_без_уточнення", ("сукн", "плать"))]


def _ключ_іменником(текст, ключ):
    """Позиція ключа, вжитого ІМЕННИКОМ, або -1.

    За ключем-іменником не йде прикметникове закінчення: «джинси» — так,
    «джинсова» — ні (`_ПРИКМЕТНИК`, той самий фільтр, що в `предмет_назви`).
    Шукає ДАЛІ по тексту, а не лише перший збіг: у «джинсова куртка з джинсів»
    перше входження прикметникове, друге — ні, і ключ усе-таки є."""
    if not ключ[-1].isalpha():
        # Ключ уже кінчається межею слова («топ », «топ,»): наступні букви — це
        # НОВЕ слово, а не закінчення цього. Без цієї межі «топ на бретелях»
        # читався як прикметник («на» збігається з `_ПРИКМЕТНИК`), і 39 топів
        # лишались без типу взагалі.
        return текст.find(ключ)
    п = текст.find(ключ)
    while п >= 0:
        if not _ПРИКМЕТНИК.match(текст[п + len(ключ): п + len(ключ) + 3]):
            return п
        п = текст.find(ключ, п + 1)
    return -1


_ГОЛОСНІ = set("аиіоуеєюяї")


def _ключ_прикметником(текст, ключ):
    """Позиція ключа, вжитого ПРИКМЕТНИКОМ, або -1 — дзеркало `_ключ_іменником`.

    Ширше за `_ПРИКМЕТНИК` на один випадок: ключ, який САМ УЖЕ КІНЧАЄТЬСЯ на «н»
    суфікса («спортивн», «домашн», «вечірн»), — тоді прикметник видно по голосній
    одразу за ключем («спортивні», «в спортивному стилі», «штани домашні»).
    `_ПРИКМЕТНИК` цього не ловить, бо чекає групу суфікса ПІСЛЯ ключа, а вона вже
    всередині. Розширення живе ЛИШЕ тут, у пошуку модифікатора: голову воно не
    чіпає, тож «Вечірня сумка-клатч» без слота лишається тим, чим була."""
    if not ключ[-1].isalpha():
        return -1
    хвіст_н = ключ.endswith("н")
    п = текст.find(ключ)
    while п >= 0:
        за = текст[п + len(ключ): п + len(ключ) + 3]
        if _ПРИКМЕТНИК.match(за) or (хвіст_н and за[:1] in _ГОЛОСНІ):
            return п
        п = текст.find(ключ, п + 1)
    return -1


def модифікатор_типу(текст, слот=None, головний=None):
    """Тип, названий ПРИКМЕТНИКОМ або хвостом складеного слова, або None.

    ЧОМУ ЦЕ ПОТРІБНО (повернення куратора на #269). Поки тип брався з першого
    ключа словника, слово «джинсова», «трикотажні», «спортивні» БУЛО типом — і
    тим тримало казуальність речі. Щойно тип став іменником, стеля формальності
    піднялась: 346 із 607 речей дістали стелю вищу на ≥ 2 («трикотажна сукня»
    5 → 9, «джинсова спідниця» 4 → 7, джогери 3 → 7), і K-KOH-05 «рівень образу
    нижче» замовкав на джинсовій сукні на весіллі.

    Слово нікуди не поділось — воно просто не тип, а МОДИФІКАТОР: для вета й
    бажання річ лишається сукнею, а формальність бере ПЕРЕТИН інтервалу іменника
    й інтервалу цього слова (`формальність.інтервал_формальності`).

    Береться рівно два випадки, як просить куратор: прикметниковий ключ будь-де
    («Джинсові штани капрі» → джинси) і хвіст складеного слова, відділений від
    голови самим дефісом («Спідниця-шорти» → шорти, «Сукня- сорочка» → сорочка).
    Слово, що стоїть окремим іменником («Сукня з піджаком»), модифікатором НЕ
    стає: там друга річ, а не ознака першої."""
    годиться = _типи_дозволені(слот)
    кандидати = []
    for т, ключі in _КЛЮЧІ_ТИПУ_З_СУКНЕЮ:
        if т == головний or not годиться(т):
            continue
        for k in ключі:
            п = _ключ_прикметником(текст, k)
            if п < 0 and т in _ТИПИ_ТКАНИНИ:
                # ДВА КЛЮЧІ, ЩО Є ЩЕ Й НАЗВОЮ ТКАНИНИ, рахуються ІМЕННИКОМ теж:
                # «Сукня міні з тонкого трикотажу», «Сукня Максі сатин джинс» —
                # тут слово стоїть після прийменника, тобто не є ні прикметником,
                # ні сусіднім словом голови, а проте каже саме про тканину речі.
                # Їх рівно два, і саме вони й породили ваду рядка 184.
                п = _ключ_іменником(текст, k)
            if п >= 0:
                кандидати.append((п, т))
    гол = предмет_типу(текст, слот) if головний is not None else None
    if гол is not None and гол[0] == головний:
        # СУСІДНЄ СЛОВО ГОЛОВИ — теж модифікатор, хоч воно й іменник:
        # «Спідниця-шорти», «Сукня- сорочка», «ШТАНИ ДЖОГЕРИ СПОРТИВНІ». Між
        # кінцем ключа й кандидатом дозволені лише власне закінчення голови
        # (букви) та роздільники — дефіс, тире, пробіл. Слово після ПРИЙМЕННИКА
        # («Сукня з піджаком») сюди не потрапляє: там друга річ, не ознака.
        кін = гол[2] + len(гол[1])
        хвіст = кін
        while хвіст < len(текст) and текст[хвіст].isalpha():
            хвіст += 1
        # «&#8211;» у назві лишається НЕРОЗКОДОВАНИМ («Сукня &#8211; сорочка»,
        # «Широкі штани &#8211; спідниця»), тож символи сутності теж роздільник.
        межа = хвіст
        while межа < len(текст) and текст[межа] in "- \u2013\u2014&#;0123456789":
            межа += 1
        for т, ключі in _КЛЮЧІ_ТИПУ_З_СУКНЕЮ:
            if т == головний or not годиться(т):
                continue
            for k in ключі:
                if межа > хвіст and текст.startswith(k, межа):
                    кандидати.append((межа, т))
    return min(кандидати)[1] if кандидати else None


def _типи_дозволені(слот):
    """Предикат «цей тип має сенс у цьому слоті».

    `_ТИПИ_ВЛАСНІ` (форми мʼяких аксесуарів і прикрас) — як доти: лише у своєму
    слоті, і при невідомому слоті не віддаються взагалі.

    ФОРМИ ВЗУТТЯ — лише коли слот ВІДОМИЙ і він не «взуття» (рядок 184). Слово
    взуття в назві одягу означає ДЕТАЛЬ, а не річ: «Лонгслів з горловиною-
    човником» і «Джемпер із акцентною горловиною "човник"» — 16 речей верху, що
    діставали тип «човники» й судились формальністю туфель. Межа та сама, що вже
    стоїть для банта й резинки, але вужча: при слоті None тип віддається, бо є
    викликачі без слота (`жнива_запис`, `фід_взуття`, гейт «Сумка-багет»), і
    мовчання там коштувало б більше за помилку."""
    свої = ТИПИ_СЛОТА.get(слот) or ()

    def годиться(т):
        """Чи можна віддати цей тип у цьому слоті."""
        if т in _ТИПИ_ВЛАСНІ:
            return т in свої
        if т in _ТИПИ_ВЗУТТЯ and слот is not None and слот != "взуття":
            return False
        return True
    return годиться


def предмет_типу(текст, слот=None):
    """(тип, ключ, позиція) за НАЙРАНІШИМ ІМЕННИКОМ-типом у тексті, або None.

    Дзеркало `предмет_назви`, тільки над `ТИП_КЛЮЧІ`. При однаковій позиції
    виграє той тип, що стоїть у словнику раніше (там специфічніші вище за
    загальні), — тож «ботфорти» не стають «чоботами».

    Складене слово: перемагає голова, крім `_ГОЛОВА_ПОСТУПАЄТЬСЯ_ФОРМІ`."""
    годиться = _типи_дозволені(слот)
    знайдені = []
    for т, ключі in _КЛЮЧІ_ТИПУ_З_СУКНЕЮ:
        if not годиться(т):
            continue
        for k in ключі:
            п = _ключ_іменником(текст, k)
            if п >= 0:
                знайдені.append((п, т, k))
    if not знайдені:
        return None
    знайдені.sort(key=lambda x: x[0])
    # СЛОТ «СУМКА» — СУМОЧНІ ТИПИ ПЕРШИМИ, як і в запасному проході. Позиція сама
    # цього не робить: у «Вечірня сумка-клатч» іменник «вечірн» стоїть перед
    # «клатч», і без цієї межі сумка діставала тип «вечірня_сукня» — рівно та
    # помилка, задля якої перед-прохід `ТИПИ_СУМОК` і зʼявився (04.09.2026).
    if слот == "сумка":
        сумочні = [x for x in знайдені if x[1] in ТИПИ_СУМОК]
        if сумочні:
            знайдені = сумочні
    п, т, k = знайдені[0]
    свої_форми = _ФОРМИ_РОДИНИ.get(т)
    if свої_форми:
        # БУДЬ-ДЕ В НАЗВІ, не лише через дефіс: «Жіноча сумка тоут замшева» і
        # «Сумка Жіноча Кросбоді з ланцюгом» пишуть форму окремим словом, і
        # вимога дефіса коштувала б 56 сумкам їхньої форми. Голова тут не
        # конкурент формі: вона сама каже «форми не знаємо».
        форми = [x for x in знайдені if x[1] in свої_форми and x[1] != т]
        if форми:
            return (форми[0][1], форми[0][2], форми[0][0])
    return (т, k, п)


def _тип_речі_обчислити(offer, слот=None):
    """Тип речі з категорії й назви. None — коли жоден ключ не збігся.

    `слот="сумка"` перевіряє сумочні типи ПЕРШИМИ. Спіймано гейтом: «Клатч
    вечірній» діставав тип «вечірня_сукня», бо ключ «вечірн» стоїть на початку
    словника, — і клатч судився як сукня з формальністю 9. Порядок словника не
    може бути правильним для всіх слотів одразу; слот — той контекст, якого
    словнику бракувало.

    None НЕ підмінюється дефолтом навмисно: тип керує формальністю, і вигаданий тип
    дав би образу формальність, якої ніхто не міряв. Скільки SKU лишились без типу —
    видно в `прогін().без_типу`, і це число і є роздільна здатність цього шару."""
    текст = ("%s %s" % (offer.get("категорія", ""), назва_суду(offer))).lower()
    # «КОСТЮМНИЙ ЖАКЕТ» — НЕ КОСТЮМ (04.09.2026, вимір: 56 речей). Ключ «костюм»
    # ловив прикметник, і жакет із костюмної тканини діставав тип «костюм» з
    # формальністю 8 — шар формальності судив жакет як діловий костюм. Прикметник
    # знімається з тексту, іменник лишається (те саме розрізнення, що в
    # аудит_слотів._прикметник).
    текст = _re_тип.sub(" ", текст)
    # 1. ПРЕДМЕТ НАЗВИ (рядок 184). Назва — не мішок слів: річчю є її ІМЕННИК, а
    #    не прикметник матеріалу. Словник по всьому тексту лишається запасним і
    #    вмикається рівно там, де предмет назви типу не має.
    # НАЗВА СУДУ, А НЕ СИРА (рядок 182 × рядок 184, зведення 24.09). Предмет
    # назви шукається в тому самому слові, яке бачить жінка: інакше #269 читає
    # іменник із рекламного речення фіду, і «Боді з бантом» знову стає «джинси»
    # за словом «денімом» у реченні. Виміряно на зведенні: 71 річ проти 2.
    _назва = _re_тип.sub(" ", назва_суду(offer).lower())
    _пр = предмет_типу(_назва, слот)
    if _пр is not None:
        return _пр[0]
    # 2. ЯК ДОТИ — СЛОВНИК У ПОРЯДКУ, але ключ і тут має бути ІМЕННИКОМ: інакше
    #    запасний прохід повертав би рівно ту помилку, яку зняв перший
    #    («Джинсова кепка» → джинси). Текст тут ширший за назву — з категорією,
    #    якою й тримаються родові типи («Аксесуари, Сумки» → сумка_без_уточнення).
    if слот == "сумка":
        for т, ключі in ТИП_КЛЮЧІ:
            if т in ТИПИ_СУМОК and any(_ключ_іменником(текст, k) >= 0 for k in ключі): return т
    _годиться = _типи_дозволені(слот)
    for т, ключі in ТИП_КЛЮЧІ:
        if not _годиться(т): continue
        if any(_ключ_іменником(текст, k) >= 0 for k in ключі): return т
    # сукня без уточнення — тип є, але формальність її НЕ визначена одним словом
    if "сукн" in текст or "плать" in текст: return "сукня_без_уточнення"
    # ── ОГОЛОШЕНИЙ ТИП ЖНИВАРКИ — ЛИШЕ ЯК ЗАПАСНИЙ (27.08.2026) ────────────────
    # Назва — точніша за розділ магазину («LeBERDES Мокасини» лежить у розділі
    # «лофери»: 51 SKU), тому слово назви йде першим. Запасний потрібен там, де
    # назви фактично нема: «Перлинний молоко» (костюм), «Бордо шоколад» (спідниця) —
    # 143 SKU каталогу жниварки мали тип у param і None тут, а без типу мовчить
    # увесь шар формальності. Приймається лише слово з власного словника типів.
    # 3. МОДИФІКАТОР ЯК ТИП — КОЛИ ПРЕДМЕТА НАЗВИ НЕМА ЗОВСІМ (рядок 184).
    #    «Сарафан джинсовий», «Трикотажний берет», «Лонгслів-поло трикотажний»:
    #    іменника-типу в назві не існує («сарафан», «берет», «лонгслів» — не
    #    ключі), тож єдине, що назва про річ каже, — це прикметник. Мовчання тут
    #    коштувало б дорожче за неточність: без типу мовчить УВЕСЬ шар
    #    формальності, і 5 джинсових сарафанів лишились би без смуги взагалі.
    #    Стеля від цього не росте — інтервал модифікатора той самий, що давав
    #    старий код (виміряно: 23 речі, у всіх стеля як на main).
    _мод = модифікатор_типу(_назва, слот)
    if _мод:
        return _мод
    _оголош = ((offer.get("параметри") or {}).get("тип") or "").strip().lower()
    # «костюм» від жниварки приймається лише коли в назві є ІМЕННИК костюм:
    # «Берет з костюмної тканини» мав param тип=костюм (4 речі) — і формальність 8.
    # (перша версія відкидала «костюм» і при ПОРОЖНІЙ назві — а «Перлинний молоко»
    # + param тип=костюм законно бере оголошений тип; гейт §? це спіймав.)
    if _оголош == "костюм" and _re_тип.search(назва_суду(offer).lower()):
        _оголош = ""
    if _оголош in ІМЕНА_ТИПІВ: return _оголош
    return None


def тип_модифікатор(offer, слот=None):
    """Тип-модифікатор речі («джинсова сукня» → джинси) або None.

    Пара до `тип_речі`: той самий текст назви, та сама межа слота. Читає це
    `формальність.інтервал_формальності` — перетином, не заміною."""
    # Той самий текст, що й у `_тип_речі_обчислити` — назва суду (рядок 182):
    # модифікатор мусить читати те саме слово, що й головний тип, інакше пара
    # розходиться саме на реченнях фіду.
    назва = _re_тип.sub(" ", назва_суду(offer).lower())
    гол = предмет_типу(назва, слот)
    return модифікатор_типу(назва, слот, гол[0] if гол else None)


ІМЕНА_ТИПІВ = frozenset([т for т, _ in ТИП_КЛЮЧІ] + ["сукня_без_уточнення", "костюм_повсякденний", "комплект"])

def розкласти_по_слотах(offers):
    """Непокриті категорії ПОВЕРТАЮТЬСЯ, а не мовчки зникають: якщо половина фіду
    не лягла в слоти, число покриття буде красиве й брехливе."""
    по_слотах, без_слота = defaultdict(list), defaultdict(int)
    for o in offers:
        s = слот(o)
        (по_слотах[s].append(o) if s else без_слота.__setitem__(
            o["категорія"] or "(без категорії)", без_слота[o["категорія"] or "(без категорії)"]+1))
    return dict(по_слотах), dict(без_слота)
