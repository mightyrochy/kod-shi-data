# `параметри.тип` (10 749 із 12 405 речей). Це те саме поле, яке `реєстри._ПОЛЯ_ФІДУ`
# 17.09 вже назвало єдиним, що «фід несе як факт, а не як рекламу», і воно там-таки
# виміряно проти `категорія_магазину` та `опис` і визнано надійнішим за обидва.
# Перевірено очима по 165 речах із назвою-реченням: `тип` збігається з розділом
# крамниці та зі слагом URL у кожній («Світшоти Худі» + /svitshot-z-vyshyvkoyu/ →
# тип=худі, а оголошено було «низ»).
#
# ЧОГО ЦЕ НЕ РОБИТЬ, І ЦЕ НАВМИСНО. `тип` НЕ переважує оголошення взагалі: він і сам
# часом читається з опису («Пояс до піджака графіт» → тип=жакет, 5 речей feelyou).
# Дорогою фактів іде РІВНО назва-речення; назва, у якої предмет є, вирішує сама
# (`предмет_назви` нижче), і справжній пояс захищає саме предмет — «Пасок…»,
# «Ремінь…», «Пояс…» лишаються поясом, хай там що каже `тип`.
#
# ДЕ ЛАМАЄТЬСЯ: крамниця, що пише в `тип` дурницю, тепер помиляється голосніше — але
# лише для речей без власної назви, де альтернатива не «назва», а «перше речення
# реклами». Обмін усвідомлений.
_РОДИНА_ПІДСЛОТА = {під: "прикраси" for під, _ in ПІД_СЛОТИ_ПРИКРАС}


def _родина_слота(с):
    """Під-слот прикрас → «прикраси», решта — як є: порівнювати оголошення з фактом
    треба на рівні РОДИНИ, інакше «прикраси» проти «брошка» читалось би як незгода."""
    return _РОДИНА_ПІДСЛОТА.get(с, с)


# ── ПРЕДМЕТ НАЗВИ, А НЕ ПЕРШЕ СЛОВО-КЛЮЧ У РЕЧЕННІ (23.09.2026, рядок 139) ──
# РУЧНИЙ ОГЛЯД КУРАТОРА, 544 речі з усіх 47 крамниць (фото картки поруч із даними
# коду): «взуття → пояс» виявилось лише частиною класу, і в зразку ~10 % речей
# стояли не в своєму слоті. Корінь один на всі: слот ставився за ПЕРШИМ ключем у
# порядку СЛОВНИКА, хоч би де той ключ стояв у реченні, — тож слово ДЕТАЛІ або
# СУПУТНИКА перемагало слово самої речі:
#   «Блуза з органзи у комплекті з шарфом»      → шарф   (а це блуза)
#   «Лляна спідниця міді з хусткою»              → шарф   (а це спідниця)
#   «ПАЛЬТО BOYFRIEND'S ЗІ ЗНІМНИМ ШАРФОМ-КЕЙПОМ» → шарф (а це пальто)
#   «Топ з біфлексу зі знімними прикрасами»      → прикраси (а це топ)
#   «Спідниця міні БЕЗ поясу»                    → пояс   (заперечення не читалось)
#   «Штани із плащівки»                          → верхній_шар (плащівка — тканина)
#
# ЧОМУ САМЕ «ПЕРШИЙ ІМЕННИК», А НЕ «ПЕРШЕ СЛОВО». Українська назва ставить
# прикметники ПЕРЕД іменником, і серед них повно слів-ключів: «Біла ДЖИНСОВА
# сукня футляр», «АТЛАСНИЙ костюм», «КОСТЮМНА тканина». Голий вимір «найраніший
# ключ за позицією» ламає 26 суконь на самому каталозі. Тому ключ із
# прикметниковим суфіксом одразу після нього (джинс-ов-а, пальт-ов-а, шкір-ян-а,
# костюм-н-ий) пропускається — це матеріал або крій, а не річ.
#
# ЦЕ НЕ НОВИЙ ПРИЛАД, А ПІДНЯТИЙ У РІШЕННЯ НАЯВНИЙ. Рівно ця функція вже два тижні
# живе в `аудит_слотів.тип_із_назви` з тим самим фільтром прикметника й тим самим
# коментарем «ПРИКМЕТНИК ≠ ТИП» — і лише ЗВІТУВАЛА («аудит НЕ виправляє мовчки»).
# Власник подивився очима й сказав виправляти; реалізація одна на обидва місця,
# `аудит_слотів` тепер кличе її звідси, щоб вимір і рішення не розійшлись.
_ПРИКМЕТНИК = re.compile(r"(ов|ев|єв|ян|ськ|н)[аиіоуеєюяї]")


def предмет_назви(назва):
    """(слот, ключ, позиція) за НАЙРАНІШИМ ІМЕННИКОМ-типом у назві, або None.

    Прикметник (матеріал або крій) пропускається: «джинсова кепка» — головний
    убір, «джинси» — низ, а ключ «джинс» той самий. При однаковій позиції виграє
    той ключ, що стоїть у `СЛОТ_КЛЮЧІ` раніше, — тож «жилет утеплений» лишається
    верхнім шаром, а не верхом.

    ПІД-СЛОТИ ПРИКРАС ШУКАЮТЬСЯ ТУТ-ТАКИ (24.09.2026, знахідка куратора на злитті
    #229): «В'язана троянда-брошка джинс» (ж-07555@likeangel) лежала у слоті «НИЗ»
    — і на головній гілці теж, — бо «брош» не є ключем `СЛОТ_КЛЮЧІ` взагалі, а
    єдиним ключем у назві виявився «джинс» на 23-й позиції, тобто слово КОЛЬОРУ в
    хвості. Сім під-слотів прикрас перевіряються ПІСЛЯ родинних ключів, тож при
    однаковій позиції родина виграє, як вигравала; під-слот перемагає лише тоді,
    коли стоїть у назві РАНІШЕ."""
    кращий = None
    for сл, ключі in list(СЛОТ_КЛЮЧІ) + list(ПІД_СЛОТИ_ПРИКРАС):
        for k in ключі:
            п = назва.find(k)
            if п < 0:
                continue
            пастки = ПАСТКИ_ПІДРЯДКА.get(k)
            if пастки and any(x in назва for x in пастки):
                continue
            if _ПРИКМЕТНИК.match(назва[п + len(k): п + len(k) + 3]):
                continue
            if кращий is None or п < кращий[2]:
                кращий = (сл, k, п)
    return кращий


def _слот_за_типом(offer):
    """Слот із `параметри.тип` — поля, яке фід несе як факт про РІД речі. None, коли
    поля нема або його слово не збігається з жодним ключем `СЛОТ_КЛЮЧІ`.

    Родину вирішує сам `тип`, члена родини (сережки ≠ каблучка) — `тип` разом із
    розділом крамниці, бо назви в таких речей нема: «Аксесуари, Брошки» + тип
    «прикраси» дає «брошка», а прогін по самому `тип` обірвався б на родині."""
    п = offer.get("параметри") or {}
    т = (п.get("тип") or "").strip().lower()
    if not т:
        return None
    return _слот_у_тексті(т, "%s %s" % (т, (п.get("категорія_магазину") or "").lower()))


def _рід_речі(offer, оголошений):
    """Слот, який переважує оголошений, або None — коли оголошення лишається.

    ДВІ ДОРОГИ, І ЯКА САМЕ — ВИРІШУЄ ПОЛЕ `назва_джерело`, не здогад:
      назва = перше речення опису → предмета в ній нема за побудовою, вирішують
        ФАКТИ запису (`параметри.тип`, далі розділ крамниці);
      назва справжня → вирішує її ПРЕДМЕТ (`предмет_назви`), бо саме він називає
        річ, а решта ключів у реченні — деталі й супутники.

    ТРИ ВИНЯТКИ, І КОЖЕН НАЗВАНИЙ:
      набір (`набір_цілий` не None) — «Лляний костюм лимонний піджак та штани
        палаццо» має ДВА предмети, і котрий із них узяти, вирішує не ця функція, а
        слот «комплект» у `фід_каталог`; рішення власника 01.09 — не чіпати;
      двослотова річ («кардиган-пальто», «жилет-бомбер») — оголошений слот є
        законним вибором із пари `ДВОСЛОТОВІ`, а не помилкою;
      предмета в назві нема зовсім (назва без жодного ключа) — тоді, і лише тоді,
        за оголошений «пояс» відповідають факти запису: інакше «пояс» лишався б
        сміттєвим слотом для всього, де трапилось це слово."""
    п = offer.get("параметри") or {}
    р = предмет_назви(назва_суду(offer).lower())
    # ДВА ВИНЯТКИ ПЕРЕВІРЯЮТЬСЯ ПЕРШИМИ, БО ЦЕ ВЛАСТИВОСТІ РЕЧІ, А НЕ НАЗВИ, і
    # тримають вони обидві дороги однаково. Спіймано виміром: «Жакет-бомбер зі
    # щільної пальтової тканини» (sunwin) має `назва_джерело=опис` і `тип=блуза`,
    # тож дорога фактів зняла б із нього верхній шар на користь верху — хоч назва
    # цілком доладна, а річ двослотова за побудовою. Те саме з «Комплект-двійка:
    # пальто прямого крою та жилет» (brenda): факт каже `тип=джинси`.
    if р is not None and (набір_цілий(offer) is not None
                          or оголошений in (_СЛОВА_ДВОСЛОТОВИХ.get(р[1]) or ())):
        return None
    if (п.get("назва_джерело") or "").strip().lower() == "опис":
        рід = _слот_за_типом(offer)
    elif р is not None:
        рід = р[0]
        if рід == "прикраси":
            # РОДИНА З ПРЕДМЕТА, ЧЛЕН РОДИНИ — З НАЗВИ, як і в `_слот_у_тексті`:
            # ключ «сереж» стоїть і в родинному списку, і в під-слотах, тож на
            # однаковій позиції виграє родина. Без цього рядка «Сережки TEXTURA»
            # з чужим оголошеним слотом дали б «прикраси», і сім рядків
            # `SLOT_NEAR_FALLBACK` знову були б мертві (приобличчева вага).
            назва_l = назва_суду(offer).lower()
            for під, кл in ПІД_СЛОТИ_ПРИКРАС:
                if any(x in назва_l for x in кл):
                    рід = під
                    break
    else:
        рід = _слот_за_типом(offer) if оголошений == "пояс" else None
    if рід is None or _родина_слота(рід) == _родина_слота(оголошений):
        return None
    return рід


# R-FP-01 — дубль `feed.слот`: категорія й атрибут — різні осі, одна в іншу не згортається.
def слот(offer, канал="жіноче"):
    """Слот речі. КАТЕГОРІЯ ПЕРЕВАЖУЄ НАЗВУ.

    `канал` — для кого цей прогін. Річ, що ЗАЯВЛЯЄ інший канал, слота не має;
    річ без заявленої статі судиться словником того самого каналу.

    ЧОМУ (знайдено 26.08.2026, вимір на дереві ager). Рядок склеювався як
    `категорія + назва`, і слово КРОЮ в назві важило стільки ж, скільки тип товару в
    категорії. Латентний доти, доки жоден ключ не збігався з назвою крою; став видимим
    при додаванні «бомбер» — тринадцять офферів
    `Женская одежда / Женские рубашки · «Рубашка-бомбер женская»` поїхали з «верх» у
    «верхній_шар», пул верху схуд, вершина композитора змінилась, §25 упав.

    ЦЕ НЕ ДУБЛЮЄ `ПАСТКИ_ПІДРЯДКА`, а доповнює її з іншого боку: пастка ловить ключ
    усередині ЧУЖОГО СЛОВА («кросбоді» ⊃ «боді») і працює навіть коли категорії нема;
    цей прохід ловить ключ у ЧУЖОМУ КРОЇ («сорочка-бомбер») і працює лише коли
    категорія щось каже. Перелічувати складені назви крою в пастках не можна — їх
    відкритий список («сукня-сорочка», «пальто-халат», «куртка-сорочка»).

    ДЕ ЛАМАЄТЬСЯ: магазин, що кладе товар у хибну категорію, тепер помиляється голосніше.
    Обмін усвідомлений: категорія — твердження продавця про товар, назва — маркетинг."""
    кат = (offer.get("категорія") or "").lower()
    # КАТЕГОРІЯ-АРТИКУЛ ВИМИКАЄТЬСЯ ТУТ, А НЕ НИЖЧЕ. Перша спроба глушила її лише
    # у проході по джерелах — і не спрацювала: `повний` склеює категорію з назвою,
    # а `_слот_у_тексті` бере ПЕРШИЙ слот за порядком словника, не за позицією в
    # рядку. «Шарф-35100» у складеному тексті все одно перемагав «Ремінь-35103».
    # Отруєний рядок треба не обходити, а не будувати.
    if _АРТИКУЛ_ЯК_КАТЕГОРІЯ.match(кат.rsplit(" / ", 1)[-1].strip()):
        кат = ""
    повний = ("%s %s" % (кат, назва_суду(offer))).lower()
    # ── НЕ ЧАСТИНА ОБРАЗУ (28.08.2026) ───────────────────────────────────────
    # ФЕЙЛ-КЕЙС, стенд на каталог_brief під наміром statement: у слот «сумка» лягла
    # «Валіза SMART рожева» за 10 600 грн (категорія «сумки та валізи» ⊃ «сумк»), і
    # композитор поставив її в офісний образ. Валіза, гаманець, косметичка, чохол —
    # речі, які не вдягають; для них слота нема, і це названо.
    # лише за НАЗВОЮ: категорія «сумки та валізи» спільна для сумок і валіз, і за нею
    # без слота лишались 117 сумок (спіймано регресією одразу)
    _назва_l = назва_суду(offer).lower()
    if any(x in _назва_l for x in НЕ_ОДЯГ):
        return None
    # ЧУЖИЙ КАНАЛ. Є заявлена стать — вона вирішує, і словник не питається:
    # жниварка вже розклала речі по двох файлах, і файл є каналом. Нема
    # заявленої статі (старий каталог) — працює словник, як працював.
    # ── ЗАЯВЛЕНА СТАТЬ ВИРІШУВАЛА ЛИШЕ В ОДИН БІК (08.09.2026, крок A6) ──────
    # ЩО ЦЕ МІНЯЄ (правило 3). `канал_речі` рахувався і використовувався РІВНО як
    # прапорець «словник не питати». Тобто річ із `стать=чоловіче` не відсіювалась
    # НІЧИМ: словник її не бачив (бо стать заявлена), а з самим значенням ніхто
    # нічого не робив — порівняти його не було з чим, бо `слот()` не знала, який
    # канал просять. Заодно половина `НЕ_НАШ_КАНАЛ` («чоловіче») не читалась
    # ніколи.
    # ВИМІР на `каталог_повний`: усі 10 770 оферів заявляють `жіноче`, тож на
    # ЦЬОМУ каталозі поведінка не змінюється ні на одну річ — діра була латентна
    # й відкрилась би на першому змішаному фіді (а чоловічий каталог у проєкті
    # вже є). Тепер канал — параметр виклику з дефолтом «жіноче»: заявлений чужий
    # канал відсікається, незаявлений і «унісекс» лишаються, як лишались.
    _кан = канал_речі(offer)
    if _кан is not None:
        if _кан != канал:
            return None
    elif any(x in _назва_l for x in (НЕ_НАШ_КАНАЛ.get(канал) or ())):
        return None
    # ── ДІАЛЕКТ ЖНИВАРКИ: КАТЕГОРІЯ ВЖЕ Є ІМЕНЕМ СЛОТА (27.08.2026) ───────────
    # ФЕЙЛ-КЕЙС, каталог_повний.xml (7597 SKU, 46 магазинів): жниварка пише категорію
    # словником САМОГО проєкту («верх», «низ», «верхній_шар», «головний_убір») і
    # дублює її в param «слот». Ключі нижче шукають підрядки типу товару («блуз»,
    # «штан»), а не імена слотів, тож «верх» і «низ» не збігались НІ З ЧИМ — далі
    # слот вирішувало слово КРОЮ з назви («спідниця-сорочка» → верх), а 378 SKU
    # (263 верх · 84 низ · 11 верхній_шар · 20 головний_убір) не діставали слота
    # взагалі й випадали з каталогу. Це той самий клас дефекту, що вже стоїть у
    # пам'яті проєкту: імена полів збігаються, словник значень — ні.
    # Категорія-ім'я слота — твердження продавця, тож переважує назву, як і решта
    # категорій. Родина «прикраси» й тут дробиться на під-слоти ЗА НАЗВОЮ (сережки ≠
    # каблучка за приобличчевою вагою), інакше сім рядків SLOT_NEAR_FALLBACK знову
    # були б мертві.
    _лист = кат.rsplit(" / ", 1)[-1].strip()
    _оголош = (_лист if _лист in ІМЕНА_СЛОТІВ else
               ((offer.get("параметри") or {}).get("слот") or "").strip().lower())
    # ОГОЛОШЕННЯ, ЯКОГО НІХТО НЕ РОБИВ (23.09.2026) — див. `_рід_речі`.
    _рід = _рід_речі(offer, _оголош)
    if _рід is not None:
        return _рід
    if _оголош in ІМЕНА_СЛОТІВ:
        if _оголош == "прикраси":
            for під, кл in ПІД_СЛОТИ_ПРИКРАС:
                if any(x in повний for x in кл):
                    return під
        return _оголош
    # КАТЕГОРІЯ-АРТИКУЛ НЕ Є КЛАСОМ РЕЧЕЙ (07.09.2026). Рядок виду «Шарф-35100»,
    # «Сукня-P29024PO» — назва ОДНОГО товару, і в новому фіді вона стоїть
    # категорією над іншими речами: «Шарф-35100» над «Ремінь-35103». Категорія
    # переважує назву за побудовою, тож ремінь ставав шарфом образу (136 речей).
    # Такий рядок не несе твердження про слот — вирішує назва.
    for джерело in (кат, повний):
        if not джерело:
            continue
        знайдено = _слот_у_тексті(джерело, повний)
        if знайдено is not None:
            return знайдено
    return None


# Імена слотів у словнику проєкту — рівно ті, що дає СЛОТ_КЛЮЧІ. Список виводиться,
# не переписується: новий слот у ключах автоматично стає розпізнаваним іменем.
ІМЕНА_СЛОТІВ = frozenset(с for с, _ in СЛОТ_КЛЮЧІ)


def _слот_у_тексті(текст, повний=None):
    """`текст` вирішує РОДИНУ слота, `повний` — члена родини.

    Розділення знайдено регресією: категорія «Прикраси» дає родину, але каблучку від
    сережок відрізняє лише НАЗВА. Прохід тільки по категорії повертав «прикраси» й
    обривав під-слоти, тобто відроджував сім мертвих рядків SLOT_NEAR_FALLBACK.
    Отже пріоритет категорії стосується вибору слота, а не деталізації всередині нього."""
    повний = текст if повний is None else повний
    for сл, ключі in СЛОТ_КЛЮЧІ:
        for k in ключі:
            if k not in текст:
                continue
            пастки = ПАСТКИ_ПІДРЯДКА.get(k)
            if пастки and any(p in текст for p in пастки):
                continue          # ключ є, але як частина чужого слова
            if сл == "прикраси":
                for під, кл in ПІД_СЛОТИ_ПРИКРАС:
                    if any(x in повний for x in кл):
                        return під
            return сл
    return None

