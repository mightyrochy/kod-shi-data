# ЧОМУ ТАК ВИХОДИЛО. `слот()` віддає оголошений слот беззастережно, бо «категорія —
# твердження продавця». Для цих речей твердження продавця там НЕМА: у jecomestudio,
# favoriteshoes і ще 28 крамниць картка не дає назви товару взагалі, і жниварка бере
# назвою ПЕРШЕ РЕЧЕННЯ ОПИСУ — сама ж це й зізнається полем `назва_джерело=опис`
# (712 речей каталогу, 30 крамниць). Далі слот вона виводить із цього рекламного
# речення: «тонкий ремінець підкреслює архітектуру стопи» → ключ «ремін» → «пояс».
# Оголошення в `категорія`/`параметри.слот` — не голос крамниці, а луна власного
# здогаду по маркетинговій фразі.
# Той самий механізм, але з іншого боку, псує слот «пояс» і там, де назва справжня:
# слово «пояс» у назві речі — ДЕТАЛЬ («Екошуба casual з поясом», «Асиметрична
# спідниця з поясом», «Зелена сукня під пояс»), а не рід речі.
#
# ЩО МІНЯЄ. У сирому записі Є факт про рід речі, якого ніхто не читав на цьому кроці:
# `параметри.тип` (10 749 із 12 405 речей). Це те саме поле, яке `реєстри._ПОЛЯ_ФІДУ`
# 17.09 вже назвало єдиним, що «фід несе як факт, а не як рекламу», і воно там-таки
# виміряно проти `категорія_магазину` та `опис` і визнано надійнішим за обидва.
# Перевірено очима по 165 речах із назвою-реченням: `тип` збігається з розділом
# крамниці та зі слагом URL у кожній («Світшоти Худі» + /svitshot-z-vyshyvkoyu/ →
# тип=худі, а оголошено було «низ»).
#
# ЧОГО ЦЕ НЕ РОБИТЬ, І ЦЕ НАВМИСНО. `тип` НЕ переважує оголошення взагалі: він і сам
# часом читається з опису («Пояс до піджака графіт» → тип=жакет, 5 речей feelyou).
# Він переважує рівно у двох названих випадках, де оголошення доведено не є
# твердженням крамниці; у другому з них справжній пояс захищено тим самим прийомом,
# який жниварка вже застосовує до крихт, — ПЕРШИМ СЛОВОМ НАЗВИ («Пасок…», «Ремінь…»,
# «Пояс…» лишаються поясом, хай там що каже `тип`).
#
# ДЕ ЛАМАЄТЬСЯ: крамниця, що пише в `тип` дурницю, тепер помиляється голосніше — але
# лише для речей без власної назви, де альтернатива не «назва», а «перше речення
# реклами». Обмін усвідомлений.
_ПЕРШЕ_СЛОВО_ПОЯСА = re.compile(r"^(пасок|паск|пояс|ремін|ремен|ремень)")
_РОДИНА_ПІДСЛОТА = {під: "прикраси" for під, _ in ПІД_СЛОТИ_ПРИКРАС}


def _родина_слота(с):
    """Під-слот прикрас → «прикраси», решта — як є: порівнювати оголошення з фактом
    треба на рівні РОДИНИ, інакше «прикраси» проти «брошка» читалось би як незгода."""
    return _РОДИНА_ПІДСЛОТА.get(с, с)


def _слот_за_типом(offer):
    """Слот із `параметри.тип` — поля, яке фід несе як факт про РІД речі. None, коли
    поля нема або його слово не збігається з жодним ключем `СЛОТ_КЛЮЧІ`.

    Родину вирішує сам `тип`, члена родини (сережки ≠ каблучка) — `тип` разом із
    розділом крамниці, бо назви в таких речей нема: «Аксесуари, Брошки» + тип
    «прикраси» дає «брошка», а прогін по самому `тип` обірвався б на родині."""
    п = offer.get("параметри") or {}
    т = (п.get("тип") or "").strip().lower()
    if not т:
        return None
    return _слот_у_тексті(т, "%s %s" % (т, (п.get("категорія_магазину") or "").lower()))


def _рід_переважує_оголошення(offer, оголошений, рід):
    """Чи є оголошений слот відлунням власного здогаду по тексту, а не голосом крамниці.

    Два названі випадки (провенанс вище): назва речі — це перше речення опису
    (`назва_джерело=опис`), або оголошено «пояс» там, де назва не починається зі
    слова пояса, тобто «пояс» у тексті був деталлю речі."""
    if _родина_слота(рід) == _родина_слота(оголошений):
        return False
    if ((offer.get("параметри") or {}).get("назва_джерело") or "").strip().lower() == "опис":
        return True
    if оголошений == "пояс":
        перше = (str(offer.get("назва") or "").split() or [""])[0].lower().strip("«»\"',.:;()[]")
        return not _ПЕРШЕ_СЛОВО_ПОЯСА.match(перше)
    return False


# R-FP-01 — дубль `feed.слот`: категорія й атрибут — різні осі, одна в іншу не згортається.
