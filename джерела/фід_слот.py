def _склад_набору(offer, розбір):
    """Коди частин комплекту з розбору або спільного словника виду."""
    частини = розбір.get("set_parts") or ()
    типи = [(ч.get("item_type"), _СЛ.СЛОТ_ТИПУ.get(ч.get("item_type")) or ч.get("slot"))
            for ч in частини if isinstance(ч, dict)]
    if not any(сл in _СЛ.КЛЮЧІ for _, сл in типи):
        текст = назва_суду(offer).lower()
        типи = [(_код_типу(т), _СЛ.СЛОТ_ТИПУ.get(_код_типу(т))) for т, ключі in ВИД_РЕЧІ_КЛЮЧІ
                if _СЛ.СЛОТ_ТИПУ.get(_код_типу(т)) not in (None, "set")
                and any(_ключ_іменником(текст, к) >= 0 for к in ключі)]
    шари = {"blazer", "jacket", "vest", "cardigan", "coat", "trench_coat"}
    if any(т not in шари and сл in ("top", "dress") for т, сл in типи):
        return "верх", "set_parts" if частини else "назва"
    if any(т in шари or сл == "outerwear" for т, сл in типи):
        return "шар", "set_parts" if частини else "назва"
    return None, "set_parts"


def _матеріали_зі_слів(текст):
    """Названі складники матеріалу кодами спільного переліку, без домислу часток."""
    import verify as перевірка
    import внутрішня_мова as мова
    текст = str(текст or "").lower()
    for пастка in перевірка.ПАСТКИ_ТКАНИНИ:
        текст = текст.replace(пастка, " ")
    словник = dict(перевірка.ВОЛОКНА)
    for поле in ("fabric", "material"):
        словник.update({значення: значення for значення in мова.ТАБЛИЦЯ[поле].values()})
        словник.update(мова.ТАБЛИЦЯ[поле])
    знайдено = []
    # Довший збіг забирає свою ділянку: екошкіра не стає також натуральною шкірою.
    for ключ in sorted(словник, key=len, reverse=True):
        код = мова.код("fabric", словник[ключ]) or мова.код("material", словник[ключ])
        if код and перевірка.на_межі(ключ, текст):
            знайдено.append(код)
            текст = re.sub(r"(?<![\w])" + re.escape(ключ) + r"\w*", " ", текст)
    return tuple(dict.fromkeys(знайдено))




def завершити_запис_речі(річ):
    """Завершити матеріальні коди після злиття перевірених свідків фото й крамниці."""
    import внутрішня_мова as мова
    текст = " ".join(str(річ.get(к) or "") for к in ("матеріал", "матеріал_верху", "волокно"))
    if not текст.strip():
        текст = річ.get("назва_показу") or річ.get("назва")
    річ["матеріал_коди"] = _матеріали_зі_слів(текст)
    погодний = річ.get("матеріал_верху") or річ.get("волокно") or річ.get("матеріал")
    річ["погодні_матеріали"] = _матеріали_зі_слів(погодний)
    матеріал = (річ.get("розбір") or {}).get("material")
    if матеріал in мова.ТАБЛИЦЯ["material"]:
        річ["погодні_матеріали"] = (матеріал,)
        річ["матеріал_коди"] = tuple(dict.fromkeys(річ["матеріал_коди"] + (матеріал,)))
    return річ


