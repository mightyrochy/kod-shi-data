def _оголошений_слот(offer, переданий=None):
    if переданий is not None:
        return переданий
    п = offer.get("параметри") or {}
    слот = str(п.get("слот") or "").strip().lower()
    if слот in ІМЕНА_СЛОТІВ or слот == "комплект":
        return слот
    лист = str(offer.get("категорія") or "").lower().rsplit(" / ", 1)[-1].strip()
    return лист if лист in ІМЕНА_СЛОТІВ or лист == "комплект" else None


def _вид_зі_слів(offer, оголошений_слот=None):
    """`річ` → (тип, слот, набір, джерело) з одного розбору виду.

    Тип визначає слот таблицею `slots.СЛОТ_ТИПУ`; оголошення може вибрати
    лише один із дозволених слотів двослотового виду. Набір читається тут-таки
    єдиним правилом і займає власний слот «комплект».
    """
    п = offer.get("параметри") or {}
    оголошений_тип = (п.get("тип") or "").strip().lower()
    оголошений = _оголошений_слот(offer, оголошений_слот)
    ключ = (str(offer.get("категорія") or ""), назва_суду(offer),
             оголошений, оголошений_тип, п.get("назва_джерело"),
             offer.get("назва"), п.get("категорія_магазину"))
    if ключ in ВИД_РЕЧІ_КЕШ:
        return ВИД_РЕЧІ_КЕШ[ключ]

    назва = re_тип.sub(" ", назва_суду(offer).lower())
    if (п.get("назва_джерело") or "").strip().lower() == "опис":
        назва = " ".join(назва.split()[:СТЕЛЯ_СЛІВ_ГОЛОВИ + 2])
        назва = re.split(r"\b(?:і|й|та|або)\b", назва, maxsplit=1)[0]
    набір = _набір_зі_слів(offer)
    знайдено = предмет_типу(назва, виключити=() if набір is True else ("комплект",))
    джерело = "назва" if знайдено else None
    if not знайдено:
        # Розділ крамниці, виведений із тієї самої деталі («Кімоно з поясом» → «пояс»),
        # не свідок: деталь після прийменника типу не дає й тут.
        без_деталі = tuple(_ТИПИ_ДЕТАЛІ) if деталь_у_назві(назва) else ()
        знайдено = предмет_типу(re_тип.sub(" ", str(offer.get("категорія") or "").lower()),
                                виключити=без_деталі + (() if набір is True else ("комплект",)))
        джерело = "категорія" if знайдено else None
    тип = знайдено[0] if знайдено else None
    # Поле `тип=костюм` у фіді осідає від ПРИКМЕТНИКА («краватка з костюмної тканини»):
    # та сама межа, що в `_набір_зі_слів` і `набір_цілий` — прикметник у сирій назві
    # замикає факт.
    прикметник = оголошений_тип in _ТИПИ_НАБОРУ and re_тип.search(str(offer.get("назва") or "").lower())
    if тип is None and оголошений_тип in ІМЕНА_ТИПІВ and not прикметник:
        тип, джерело = оголошений_тип, "оголошене"
    if набір is True:
        тип, слот_виду = _тип_набору_зі_слів(offer), "комплект"
    else:
        код = _код_типу(тип)
        допустимі = _СЛ.ДВОСЛОТОВІ_ТИПИ.get(код, ())
        дозволені = tuple(_СЛ.КЛЮЧІ[x] for x in допустимі)
        слот_виду = (оголошений if оголошений in дозволені else
                     _СЛ.КЛЮЧІ.get(_СЛ.СЛОТ_ТИПУ.get(код)))
        if слот_виду is None:
            слот_виду = оголошений
    if слот_виду == "комплект":
        набір = True
    результат = (тип, слот_виду, набір, джерело)
    if len(ВИД_РЕЧІ_КЕШ) < 300000:
        ВИД_РЕЧІ_КЕШ[ключ] = результат
    return результат


def слот(offer, канал="жіноче"):
    """Слот є похідним від виду речі; чужий заявлений канал відсікається."""
    запис = offer.get("запис_речі")
    if запис is not None:
        return запис.get("слот") if канал in запис.get("канали", (канал,)) else None
    if "тип" in offer or "слот" in offer:
        return offer.get("слот")
    заявлений = канал_речі(offer)
    назва = назва_суду(offer).lower()
    if (заявлений is not None and заявлений != канал) or any(x in назва for x in НЕ_ОДЯГ):
        return None
    if заявлений is None and any(x in назва for x in (НЕ_НАШ_КАНАЛ.get(канал) or ())):
        return None
    return вид_речі(offer)[1]


def набір_цілий(offer):
    """Тонка обгортка над єдиним читачем виду."""
    return вид_речі(offer)[2]


def _модифікатор_зі_слів(offer, слот=None):
    """Тип-модифікатор речі («джинсова сукня» → джинси) або None.

    Пара до `тип_речі`: той самий текст назви, та сама межа слота. Читає це
    `формальність.інтервал_формальності` — перетином, не заміною."""
    # Той самий текст, що й у `_тип_речі_обчислити`, — назва суду:
    # модифікатор мусить читати те саме слово, що й головний тип, інакше пара
    # розходиться саме на реченнях фіду.
    назва = re_тип.sub(" ", назва_суду(offer).lower())
    гол = предмет_типу(назва, слот)
    return модифікатор_типу(назва, слот, гол[0] if гол else None)


