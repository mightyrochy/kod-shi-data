# ── МНОЖНИКИ ІНДУКЦІЇ (R-CHEV-13, R-CHEV-15) ────────────────────────────────
C_REF_ІНДУКЦІЇ = 36.0   # T4 · фольклорна константа. Жодне джерело її не дає.
                        # 36 — хрома «насиченого смарагда» з прикладу самого правила,
                        # тобто точка, у якій множник доходить до 1.0. Калібрується
                        # лише на вердиктах носіння.

def _множник_хроми(хрома_речі):
    """R-CHEV-13. Монотонний, обрізаний на 1.0. Не крива: джерело прямо каже, що
    метод парних порівнянь форми кривої не дає."""
    if хрома_речі is None:
        return 1.0, ("хроми речі не передано — множник 1.0. Це НЕ нейтрально: так "
                     "приглушена річ дістає вагу насиченої (R-CHEV-13)")
    c = max(0.0, float(хрома_речі))
    м = min(c / C_REF_ІНДУКЦІЇ, 1.0)
    return round(м, 3), ("хрома речі C*%.0f → множник %.2f (C_ref=%.0f, ФОЛЬКЛОРНА "
                         "константа: джерела не дають). Напрям T2 — індукція росте з "
                         "насиченістю оточення; форма кривої НЕ встановлена, тому "
                         "лінійно й з обрізанням" % (c, м, C_REF_ІНДУКЦІЇ))

# Лінії контакту: наскільки близько до обличчя реально ТОРКАЄТЬСЯ край речі.
# Це НЕ радіус і не спадання — це названі геометрії з фіду. Числа порядкові.
КОНТАКТ = {
 "щелепа":      dict(м=1.00, приклад="шарф, зав'язаний на горлі; водолазка"),
 "ключиця":     dict(м=0.75, приклад="лацкан жакета; круглий виріз"),
 "декольте":    dict(м=0.55, приклад="глибокий V; відкритий виріз"),
 "плече":       dict(м=0.45, приклад="бретель; відкрите плече"),
 "без_контакту": dict(м=0.30, приклад="річ біля обличчя, але не торкається"),
}

# Виведення лінії контакту з полів, які речі ВЖЕ несуть. Це не новий вимір — це
# використання наявного. `виріз` у системі двійковий ("закритий"/"відкритий"), тож
# роздільність тут груба й це сказано: закритий верх торкається щелепи або ключиці
# залежно від типу, відкритий — декольте. Тонша шкала (водолазка проти круглого
# вирізу) вимагає тоншого поля у фіді й доти не вигадується.
_ТИП_У_КОНТАКТ_ЗАКРИТИЙ = {
 "водолазка": "щелепа", "гольф": "щелепа", "шарф": "щелепа", "хустка": "щелепа",
 "светр": "ключиця", "сорочка": "ключиця", "блуза": "ключиця", "жакет": "ключиця",
 "пальто": "ключиця", "тренч": "ключиця", "блейзер": "ключиця",
}

def контакт_із_речі(річ):
    """(контакт, чому). Лінія контакту з полів `виріз` і `тип`, які річ уже несе.
    None — коли жодне поле не дає підстави; тоді множник 1.0 і це сказано вголос.

    ⚠ ПОРЯДОК ГІЛОК: `виріз` перевіряється ПЕРШИМ, тож на суперечливій речі
    {тип:'водолазка', виріз:'відкритий'} двійковий виріз б'є точний тип. Наряд
    Н-palette-2-101 велів поміняти порядок ЗА ПОТРЕБИ — потреби нема, і це
    ВИМІРЯНО, а не припущено: на живому шляху (`стенд_знімок.дим`) речі несуть
    `тип` ('светр', 'штани', 'черевики') і НЕ несуть `виріз` жодного разу —
    0 речей із `виріз` із 3, отже 0 суперечностей. Поки фід `виріз` не пише,
    зміна порядку не змінила б жодного виходу, а зробила б гілку без виміру."""
    if not isinstance(річ, dict): return None, "річ не словник"
    тип = str(річ.get("тип") or "").strip().lower()
    виріз = річ.get("виріз")
    if виріз == "відкритий":
        return "декольте", "виріз «відкритий» → контакт на декольте (груба шкала: поле двійкове)"
    if тип in _ТИП_У_КОНТАКТ_ЗАКРИТИЙ:
        к = _ТИП_У_КОНТАКТ_ЗАКРИТИЙ[тип]
        return к, "тип «%s» + виріз «%s» → контакт на «%s»" % (тип, виріз or "не вказано", к)
    if виріз == "закритий":
        return "ключиця", "виріз «закритий», тип невідомий → контакт на ключиці (дефолт)"
    return None, ("ні `виріз`, ні відомий `тип` — лінія контакту не виводиться. "
                  "R-CHEV-15 замовкає, множник 1.0")


def _множник_контакту(контакт):
    """R-CHEV-15. Індукція максимальна на ЛІНІЇ КОНТАКТУ і спадає з відстанню від
    неї, лишаючись ненульовою через проміжок (звідси 0.30, а не 0).

    ⚠ Chevreul одиниць не дає: форма (монотонне спадання, ненульове на проміжку) —
    T1, будь-яка числова константа — T4. Тому радіуса тут НЕМА: є названі геометрії,
    і множник ПОРЯДКОВИЙ. Коли геометрії не передано, множник 1.0 і це сказано."""
    if not контакт:
        return 1.0, ("лінії контакту не передано — множник 1.0. Керівна змінна за "
                     "Chevreul §10 — відстань від ЛІНІЇ КОНТАКТУ, а не близькість "
                     "слота: шарф на горлі й лацкан жакета обидва «біля обличчя», але "
                     "контакт першого на щелепі, другого на ключиці")
    k = КОНТАКТ.get(контакт)
    if not k:
        return 1.0, "геометрія контакту «%s» невідома — множник 1.0" % контакт
    return k["м"], ("контакт на «%s» (%s) → множник %.2f. Порядкове число, не вимір: "
                    "Chevreul показує спадання маскуванням, без одиниць"
                    % (контакт, k["приклад"], k["м"]))

# R-CHEV-04 — дубль `palette.нейтраль_якір`: сірий — тіло, що ПРИЙМАЄ ефект, не джерело.
def нейтраль_якір(F, source="uncontrolled", слот="верх", intent="conventional", near=None,
                  драп=None, мета="лестити", хрома_речі=None, контакт=None,
                  дистанція=None):
    """Вибір нейтралі-якоря за температурою ОСОБИ — неперервно, без класів.

    ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after):
      before — температура нарізалась на 4 класи з обривом на |тепло|=0.5, індексувала
               готову дугу тону, впорскувалась БІНАРНО й ОДНАКОВО в усі нейтральні слоти
               (а фільтр фіду її взагалі не читав — ранній return у підходить);
      after  — вікно нейтралі по b* рухається неперервно за теплом особи, а СИЛА
               переваги = |тепло| × near: та сама кемел-нейтраль виходить обов'язковою
               в шарфі (near 1.0) і практично вільною в штанях (near 0.05). Розвилка
               строгості більше не вирішується суперечкою — її вирішує РОЗМІЩЕННЯ.

    ДОКАЗОВА БАЗА — З ВЛАСНОГО КОРПУСУ, НЕ З БЛОГІВ (виправлено після закиду про
    авторитетність джерел; раніше тір ставили стилістичні сайти, що неприйнятно):
      · ІСНУВАННЯ приобличчевого ефекту — R-CHEV-06 (+ study-note_03): закон
        симультанного контрасту, відтворювана перцептивна фізика (induction +
        contrast of tone), підтверджена сучасним зором (латеральне гальмування,
        colour induction). Колір біля обличчя кидає комплементар на шкіру. Це
        ЄДИНЕ, що тут має сильний тір, і воно виправдовує САМУ ВАГУ near, а не
        напрям переваги.
      · НАПРЯМ переваги (тепле до теплого) — конвенція: R-CHEV-07 (T3) прямо
        називає таблицю напрямів «інструментом ПІД МЕТУ, не вердиктом»;
        R-PC-01 (T2·hard) — сезонні/підтонові прескрипції мають слабку доказовість;
        R-CHEV-12/R-PC-06 (T4·hard) — warm-cool таксономія це конвенція, не механізм;
        R-TYP-04 (hard) — впевнений типологічний вердикт СИСТЕМІ ЗАБОРОНЕНО.
      · R-PC-03 (T2): контраст-рівень колориту — ЗАХИЩЕНІША вісь за hue/warm-cool.
        Отже ця функція працює на слабшій осі й не має перебивати контрастні вікна.
      · R-PC-04 (T1·hard): не авто-діагностувати колорит із фото. Первинне джерело —
        СТИМУЛЬНА ЕЛІСІТАЦІЯ (драп: золото/срібло, вершковий/оптичний білий —
        питання, які вже ставить колір_образу.білі), фото — лише low-confidence assist;
        поля `джерело` і `впевненість` обов'язкові. Тому вага вікна від фото
        ОБМЕЖЕНА стелею й повної сили без елісітації не досягає.
      · Практикарський шар (стилістичні сайти) лишається лише як джерело РЕМОНТУ,
        не як підстава тіру: замість «не носи» — «тримай пальто розстібнутим і
        поклади нейтраль потрібної температури біля обличчя» (вставити проміжний
        шар). Це конвенція (T3), корисна як формулювання ремонту.

    ДИСЕНТ ЗБЕРЕЖЕНО (не вето): редакційна мода (ASOS) радить ПРОТИЛЕЖНЕ — брати
    нейтраль протилежної температури свідомо, «температурна напруга пожвавлює образ».
    Тому це ніколи не заборона: сила лишається силою, а `розвилка` каже це вголос.

    ХРОМА МОДУЛЮЄ КОНФЛІКТ: приглушений (посірілий) кемел конфліктує слабше за
    насичений золотий — ахроматика (C*→0) взагалі температуро-гнучка. Тому вікно
    ширшає, коли слот і так тримається низької хроми.

    ДВІ ОСІ ОКРЕМО: `сила_переваги` — сила властивості (|тепло|×near, самовідносна,
    калібрування не треба); `надійність` — якість виміру підтону (reliability(source)).
    Надійність звужує ВІКНО (сила ≤ верифікація), але не підмінює силу властивості."""
    т = температура(F, source, intent)
    # ── ОДИН СВІДОК НА ОДНЕ ПИТАННЯ (Н-palette-2-100, 11.09.2026) ────────────
    # `температура` вище вже винесла вирок про придатність знака осі підтону й
    # віддає його полем `знак_осі_придатний`. Читати `F['шкіра']` тут вдруге
    # означало б завести другого свідка: досить комусь уточнити умову в
    # `температура` — і вікно нейтралі лишиться на старій, мовчки.
    знак_ок = т.get("знак_осі_придатний") is not False
    # ── ЗАПАСНА ВАГА ЙДЕ ЧЕРЕЗ ОДНУ ФУНКЦІЮ, І ВОНА ЗНАЄ СЦЕНУ (K-COND-04) ───
    # Тут стояло читання словника `SLOT_NEAR_FALLBACK` напряму — третє місце в
    # системі, яке підставляло приобличчеву вагу своїм способом. Тепер усі троє
    # (`outfit.елементи`, `composer._near_слота` і цей рядок) питають
    # `колір_образу.near_слота`, а та зсуває базу на відстань огляду. Наслідок
    # саме тут не косметичний: `near_вага` множиться в `сила_переваги`, а та —
    # у `вага_вікна`, тобто в ШИРИНУ температурного вікна нейтралі, яке їде
    # запитом у каталог. На «розмові» вікно нейтралі біля обличчя вужчає, на
    # «повний зріст» — ширшає, і рівно так само для далеких слотів навпаки.
    # `дистанція=None` (сценарій не назвав відстані) лишає число, яке було.
    near_вага = float(_КОЛІР.near_слота(слот, дистанція) if near is None else near)
    if not т.get("придатно") or т.get("тепло_сила") is None:
        return dict(придатно=False, причина=т.get("причина"), деградація=т.get("деградація"),
                    b_min=None, b_max=None, сила_переваги=0.0, near=near_вага,
                    дистанція=дистанція)
    # тепло_сила з colorspace — це (h°−57)/12, обрізане на ±1.5 (самовідносна магнітуда,
    # не [−1,1]). Нормуємо тією ж шкалою, а не вигаданою.
    w_фото = max(-1.0, min(1.0, float(т["тепло_сила"]) / B_НЕЙТРАЛЬ["шкала_тепло_сили"]))
    надійність_фото = reliability(source)["undertone"]
    # R-PC-04: фото зі стелею — саме лише фото не дає повної ваги вікна
    впев_фото = min(ФОТО_СТЕЛЯ, надійність_фото / max(1e-6, MIN_TO_EMIT) * ФОТО_СТЕЛЯ)
    # ── ЗНАК, ЯКИЙ НЕ ВИМІР, НЕ СТАЄ ВАГОЮ ВІКНА (Н-V04-013, 11.09.2026) ─────
    # Це той самий хід, який `температура` вже робить гілкою `знак_придатний is
    # False and not знак_з_елісітації`: `colorspace._температура_шкіри` придушує
    # ЗНАК осі підтону там, де вимір його не тримає («вісь одностороння на цій
    # популяції» — `audit_anchors`, перевірка B: європейський діапазон тону шкіри
    # 54.0–77.8°, а межа «холодна» стоїть на h<51.0°, куди популяція не заходить
    # зовсім). `нейтраль_якір` цього не слухала й брала `тепло_сила` беззастережно.
    # Ціна вимірна: на #c9b183 з `source='protocolized'` вікно нейтралі виходило
    # зсунутим (вага 0.45, b* [−16.2..42.0]) у бік, якого ніхто не стверджував,
    # і цей бік їхав у запит до каталогу як фільтр речей.
    #
    # ВПЕВНЕНІСТЬ ГАСНЕ РАЗОМ ІЗ ВАГОЮ, і це не косметика: формула нижче ділить
    # на `ел['впевненість'] + впев_фото`, тож ненульове фото при нульовій вазі
    # РОЗБАВЛЯЛО Б елісітацію — єдиний канал, який тут лишається живим, слабшав
    # би без підстави.
    #
    # ЩО ЦЕ ПОСЛАБЛЮЄ (сказано вголос, бо це послаблення, а не посилення): у всіх,
    # хто карток не заповнив, температурне вікно нейтралі стає вільним, рядки b*
    # зникають із запиту у фід, пул росте, а колірна дисципліна нейтралей падає
    # до нуля. Це і є бажана поведінка: правило замовкає, коли входу нема.
    if not знак_ок:
        w_фото, впев_фото = 0.0, 0.0
    # **драп валився TypeError на будь-якому зайвому ключі — фільтруємо до контракту
    ел = (тепло_з_елісітації(**{k: v for k, v in драп.items()
                                if k in ("білий", "метал", "нейтралі")})
          if isinstance(драп, dict)
          else dict(w=None, впевненість=0.0, джерело="елісітації не було"))
    if ел.get("w") is not None:
        # первинне джерело — елісітація; фото лишається assist і лише зважується
        w = (ел["w"] * ел["впевненість"] + w_фото * впев_фото) / max(1e-6, ел["впевненість"] + впев_фото)
        впевненість = min(1.0, ел["впевненість"] + 0.5 * впев_фото)
        джерело = "елісітація (первинна) + фото (assist)"
    else:
        w, впевненість, джерело = w_фото, впев_фото, (
            "знак осі підтону не стверджується (audit_anchors B) — бік лише з "
            "елісітації (єдине джерело; фото тут не вимір)"
            if not знак_ок else "фото (low-confidence, R-PC-04)")
    # ── R-CHEV-13 + R-CHEV-15: сила індукції залежить не лише від ЛЮДИНИ ──────
    # ЩО БУЛО: `сила_переваги = |w| × near_вага`, де w — підтон НОСІЯ, а near_вага —
    # близькість СЛОТА до обличчя. Хроми самої речі в добутку НЕМАЄ, і геометрії
    # контакту теж. Наслідок конкретний: приглушений кардиган-шавлія (C*14) і
    # насичений смарагдовий кардиган (C*36) в одному слоті діставали ІДЕНТИЧНУ вагу
    # індукції — хоча за джерелом смарагд тисне приблизно вдвічі-втричі сильніше, і
    # саме він потребує нейтралі біля коміра.
    #
    # R-CHEV-13 (Ratnasingam & Anderson 2017, експ.2, 9 спостерігачів): індукція росте
    # з насиченістю оточення незалежно від того, чи ділять оточення й ціль тон —
    # четвертий закон Кіршмана узагальнюється. НАПРЯМ установлено, ФУНКЦІОНАЛЬНА ФОРМА
    # ні: метод парних порівнянь не дає ні швидкості росту, ні того, чи крива
    # насичується. Тому множник МОНОТОННИЙ і обрізаний — не крива.
    # ⚠ `C_ref` НЕ ДАЄ ЖОДНЕ ДЖЕРЕЛО. Це фольклорна константа (T4·hint), і вона стоїть
    # у реєстрі як така. Заборонено екстраполювати вище протестованого діапазону:
    # крива може насичуватись або перевертатись.
    #
    # R-CHEV-15 (Chevreul §10–11, T1 для ФОРМИ): індукція локалізована на КРАЮ і
    # спадає з відстанню від лінії контакту, лишаючись ненульовою через проміжок.
    # Керівна змінна — відстань від лінії контакту, а не близькість СЛОТА: шарф,
    # зав'язаний на горлі, і лацкан жакета обидва «близькі», але лінія контакту шарфа
    # на щелепі, а лацкана — на ключиці. ⚠ Chevreul не дає одиниць; будь-яка числова
    # константа спадання фольклорна. Тому радіуса НЕ кодуємо — беремо названу
    # геометрію контакту, коли вона є, і чесно кажемо, коли її нема.
    хрома_множник, хрома_нота = _множник_хроми(хрома_речі)
    контакт_множник, контакт_нота = _множник_контакту(контакт)
    сила_переваги = round(abs(w) * near_вага * хрома_множник * контакт_множник, 3)
    # R-CHEV-08: система несе МЕТУ людини. Гармонізація — лише одна з мет; при «приховати»
    # чи «експресія» температурна перевага лишається порадою й вікна не звужує.
    гармонізує = (мета == "лестити")
    вага_вікна = max(0.0, min(1.0, сила_переваги * впевненість)) if гармонізує else 0.0
    # Вікно — це БІК, а не смуга: при повній вазі лишається половина простору нейтралей
    # на температурі особи, при нульовій — весь простір. Внутрішня межа їде неперервно.
    ХОЛ, ТЕП = B_НЕЙТРАЛЬ["холод_мін"], B_НЕЙТРАЛЬ["тепло_макс"]
    def _лерп(a, b, t):
        """Лінійна інтерполяція від `a` до `b` на частці `t` ∈ [0, 1]."""
        return a + (b - a) * t
    if w >= 0:
        b_min = _лерп(ХОЛ, B_НЕЙТРАЛЬ["межа_тепла"], вага_вікна); b_max = ТЕП
    else:
        b_min = ХОЛ; b_max = _лерп(ТЕП, B_НЕЙТРАЛЬ["межа_холоду"], вага_вікна)
    бік = "теплу" if w > 0 else ("холодну" if w < 0 else "будь-яку")
    далекі = [s for s, v in _КОЛІР.SLOT_NEAR_FALLBACK.items() if v <= 0.2]
    return dict(придатно=True, слот=слот, near=round(near_вага, 2),
                тепло_особи=round(w, 2), сила_підтону=round(abs(w), 2),
                сила_переваги=сила_переваги, вага_вікна=round(вага_вікна, 2),
                хрома_множник=хрома_множник, хрома_нота=хрома_нота,
                контакт_множник=контакт_множник, контакт_нота=контакт_нота,
                # поля обов'язкові за резолюцією конфлікту R-PC-04 ↔ словник
                джерело=джерело, впевненість=round(впевненість, 2), мета=мета,
                # `колір_образу.температура_нейтралі` і `суд_образу.метали` будують на цьому
                # полі своє `ламається`: без нього знахідка не може пояснити, чому
                # її нема (Н-V04-013, крок 2).
                знак_осі_придатний=т.get("знак_осі_придатний"),
                гармонізує=гармонізує,
                питання_елісітації=ел.get("питання"),
                надійність=round(надійність_фото, 2),
                b_min=round(b_min, 1), b_max=round(b_max, 1),
                вільно=(вага_вікна < 0.05),
                дистанція=дистанція,
                нота=("слот %s: near %.2f%s × сила підтону %.2f → перевага %.2f; вікно b* "
                      "[%.1f..%.1f] (%s нейтраль)"
                      % (слот, near_вага,
                         "" if near is not None or дистанція is None
                         else " (вага на «%s»)" % дистанція,
                         abs(w), сила_переваги, b_min, b_max, бік)),
                ремонт_якщо_проти=("не викидати річ: покласти нейтраль потрібної температури "
                                   "БІЛЯ ОБЛИЧЧЯ (шарф/топ/розстібнутий шар), а протилежну "
                                   "лишити далеко — " + ", ".join(sorted(далекі))),
                розвилка=("температура-матч (лестити обличчю) vs свідома температурна напруга "
                          "(редакційна мода); друге законне — тому це сила, не вето"),
                тіри=dict(існування_ефекту="R-CHEV-06 + study-note_03: симультанний контраст, "
                                            "перцептивна фізика — виправдовує вагу near",
                          напрям_переваги="T3 конвенція (R-CHEV-07 «інструмент під мету, не "
                                          "вердикт»; R-PC-01 слабка доказовість; R-CHEV-12 "
                                          "warm-cool = конвенція; R-TYP-04 вердикт заборонено)",
                          вісь="R-PC-03: контраст — захищеніша вісь; ця слабша й не перебиває",
                          вхід="R-PC-04 (T1·hard): фото = low-conf assist, первинне — елісітація",
                          числа="T3 — межі b*, центри й ширини не калібровані",
                          пропорція="80/20 знайдено в ОДНОМУ джерелі → як поріг не кодую"))

# ── R-COL-16: ВІСЬ РЕЧІ ПРОТИ ЛЮДИНИ — b*, КЛЮЧ НОСІЯ — ОЧІ (19.09.2026) ─────
# КОРПУС (тема-2:841, T2 · hint). Perrett & Sprengelmeyer 2021: коли спостерігач
# добирає колір одягу під обличчя, вісь, якою рухається вибір, — b* речі
# (жовто-синя), а не клас «тепла/холодна» людини: 77 % (74/96) обрали ВИЩИЙ b*
# до темнішого обличчя. Перший запис називав змінну носія «меланін, ITA шкіри».
# РЕВІЗІЯ ТОГО САМОГО КОРПУСУ (тема-2:1712, §6.1; K-COND-02; R-COL-17). Той самий
# лабораторій 2023 розвів змінні: шкіру перетворили між низьким і високим
# меланіном при тих самих очах — вибір НЕ змінився; очі пересадили — вибір
# пішов за очима (світлі → холодніше, темні → тепліше). §6.1 дослівно: «b_min/
# b_max keyed on ITA is the wrong key; the key is iris lightness/warmth», а
# K-COND-02: засмага (зсув L*/b* шкіри в межах однієї людини) НЕ має перемикати
# вікна. Тому ключ тут — b* РАЙДУЖКИ; ITA шкіри читається й віддається в полі
# лише для сліду (щоб було видно, що він знав і не скористався), а запасним
# ключем не стає: інакше `profile.засмага` рухала б вікно, чого корпус забороняє.
# ЧИСЛА. Межа «свого боку» — `реєстр_правил.C["b_нейтралі"]` (b*>3 теплий бік,
# b*<−1 холодний, між ними вісь мовчить) — та сама конвенція T3, якою система вже
# судить бік нейтралі; окремого числа під R-COL-16 не заведено (двійник).
# СИЛА. Корпус: «measure discriminating power on a real feed before assigning any
# force above hint» — hint, регістр репліка. У пулі це ПОРЯДОК серед рівних за
# колірною відстанню (`composer._кандидати_на_слот`), не фільтр і не вікно: вікно
# на хроматичній гілці при силі hint спорожняло б слот, а не радило б.
def бік_b_проти_людини(F):
    """Бік осі b* для речей біля обличчя, з кольору ОЧЕЙ. `вхід=False`, коли очей у
    профілі нема або їх b* лежить в ахроматичній смузі — тоді правило чесно мовчить."""
    межа_т, межа_х = _РЕЄСТР.C["b_нейтралі"]
    очі = (F or {}).get("очі") or {}
    шк = (F or {}).get("шкіра") or {}
    ita = шк.get("ITA"); ita_смуга = шк.get("ITA_смуга")
    # `colorspace.поля_риси` кладе рисі b* полем `b`; hex — запас на профіль, де
    # риса прийшла без розкладу (тест, ручний JSON).
    b = очі.get("b"); b_чому = None
    if b is None and очі.get("hex"):
        # п.14 (20.09.2026): `hx` на рядку кидає лише ValueError (не «#rrggbb»).
        # Це необов'язковий запасний вхід, тож ловиться вузько — і споживач бачить
        # у `чому` саме «hex не читається», а не «очей у профілі нема».
        try: b = hx(очі["hex"])[2]
        except ValueError:
            b_чому = "hex очей «%s» не читається як #rrggbb — бік b* не читається" % очі["hex"]
    база = dict(правило="R-COL-16", риса="очі", тір="T2", сила="hint",
                межі=dict(теплий_від=межа_т, холодний_до=межа_х),
                ITA_шкіри=ita, ITA_смуга=ita_смуга,
                ITA_не_ключ="тема-2 §6.1 / K-COND-02: меланін шкіри вибору не рухає, очі рухають")
    if b is None:
        return dict(база, вхід=False, бік=0, b_очей=None,
                    чому=b_чому or "у профілі нема кольору очей — бік b* не читається")
    b = float(b)
    if b > межа_т: бік = 1
    elif b < межа_х: бік = -1
    else: бік = 0
    if бік == 0:
        return dict(база, вхід=False, бік=0, b_очей=round(b, 1),
                    чому="b* очей %.1f в ахроматичній смузі [%.1f..%.1f] — бік не стверджується"
                         % (b, межа_х, межа_т))
    return dict(база, вхід=True, бік=бік, b_очей=round(b, 1),
                джерело="b* райдужки (Perrett 2023: вибір іде за очима)",
                чому="b* очей %.1f — %s бік жовто-синьої осі; речі біля обличчя з того самого "
                     "боку читаються рівніше (T2 · hint, порядок, не вікно)"
                     % (b, "теплий" if бік > 0 else "холодний"))


def бік_b_речі(lab):
    """Бік b* самої речі тими самими межами `b_нейтралі`: +1 / −1 / 0 (смуга)."""
    межа_т, межа_х = _РЕЄСТР.C["b_нейтралі"]
    b = float(lab[2])
    return 1 if b > межа_т else (-1 if b < межа_х else 0)
