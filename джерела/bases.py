# K-COL-06: C* < 12 — ахроматична сім'я, тону з неї не взяти.
# ОДНА МЕЖА, ОДНЕ МІСЦЕ (19.09.2026). Стояло `АХРОМАТИЧНА_МЕЖА = 12.0` голим
