# -*- coding: utf-8 -*-
"""РЕКОМЕНДОВАНІ ОСНОВИ — НЕПЕРЕРВНИЙ РАНГ, А НЕ КЛАС І ТАБЛИЦЯ.

ЩО БУЛО ЗЛАМАНО (виміряно, не переказано).

  ВИМІР 1. Три навмисно різні профілі діставали ТОТОЖНИЙ список рекомендацій:
        світла холодна   клас=нейтральна сила=0.15 → #26384A #343A3F #171717 …
        тепла середня    клас=нейтральна сила=0.03 → #26384A #343A3F #171717 …
        темна глибока    клас=нейтральна сила=0.11 → #26384A #343A3F #171717 …
  Причина: `_основи` рахувала ОДНУ вісь (підтон), рубала її порогом
  |тепло_сила| > 0.5 на чотири класи й діставала з таблиці готовий список.
  На реальних профілях сила підтону — 0.03…0.15, тобто поріг не переходить
  ніхто, і всі отримують гілку «нейтральна». Клас спрацьовує лише на
  синтетичних крайнощах (0.99 і 1.5).

  ВИМІР 2. Світлота й хрома людини на рекомендацію не впливали ЗОВСІМ, хоча
  обидві виміряні й обидві надійніші за підтон: reliability(uncontrolled) дає
  value 0.80, contrast 0.85, chroma 0.35, undertone 0.15. Тобто найнадійніша
  вісь не використовувалась, а найненадійніша вирішувала все.

  ВИМІР 3. Відповіді на картки біля обличчя (золото/срібло, теплий/холодний
  білий, теплі/холодні нейтралі) не міняли список НІ НА ОДИН КОЛІР — перевірено
  прогоном із трьома різними самозвітами, вихід побайтово однаковий. Людину
  питали й відповідь викидали.

ЧОМУ САМЕ ТАК (підстава з корпусу, не винахід).
  тема-2 міряє ціну кроку по кожній осі в ΔE00 на чипах Манселла:
        Value, ΔV = 1            8.02
        Chroma, ΔC = 2           3.27
        Hue, один крок 2.5       3.55
  і робить із цього висновок дослівно: «One Value step costs 2.5× a Chroma step
  and 2.3× a Hue step. Anything that treats a step of value as comparable to a
  step of chroma is wrong by a factor of two and a half.»
  Стара таблиця робила рівно це: рахувала ЛИШЕ тон і ігнорувала світлоту.
  Тут ваги беруться просто з тих чисел.
  тема-2 також окремо каже, що зв'язок «людина → сезон» — неваліданована
  надбудова (R-CHEV-12), тоді як самі осі (value/chroma/hue) валідовані. Тому
  класу людини тут нема взагалі: є три осі й ранг по них.

ЧОГО ЦЕЙ МОДУЛЬ НЕ ВМІЄ:
  · він не знає, чи його ранг збігається з думкою стиліста: золотого набору
    «людина × колір → так/ні» не існує, і поки його нема, ранг лишається
    T3-конвенцією, а не виміром. Тому в UI він і зветься «рекомендовані»,
    а не «ваші кольори», і сусідній ряд «інші» ніколи не ховається.
  · ціль світлоти виводиться з контрасту особи (волосся↔шкіра). Для сивого
    або багатотонного волосся контраст сам по собі хисткий — тоді вага осі
    падає разом із `надійність_контрасту`, але не зникає.
  · хрома з фото має надійність 0.35, тож без самозвіту про барви ця вісь
    важить менш ніж утричі від номіналу.
"""

import math

# ── ВАГИ ОСЕЙ: ціна одного кроку в ΔE00 (тема-2, чипи Манселла) ──────────
# Не нормовані «на око» — це прямо ті числа. Нормування нижче лише зводить
# суму до 1, співвідношення 8.02 : 3.27 : 3.55 лишається недоторканим.
# ТРЕТЯ ВЕРСІЯ ЦІЄЇ ОСІ, І ЦЬОГО РАЗУ ЇЇ ПРОСТО НЕМА В БАЛІ.
# Дві попередні були неправильні, обидві піймані на реальному профілі:
#   (1) `value_gap` як цільова відстань → на світлій блондинці ціль вийшла
#       0.5 L*, тобто «вдягніть колір власного обличчя»;
#   (2) зона [min,max] по шкірі й волоссю як умова → чорний і нейві опинились
#       «за межами», і список звузився до семи кольорів.
# КОРІНЬ ОБОХ ОДИН. Я брав вимір Манселла (крок Value = 8.02 ΔE00) — це
# твердження про ПЕРЦЕПТИВНУ ВІДСТАНЬ між двома кольорами — і використовував
# як вагу в оцінці ПРИДАТНОСТІ кольору людині. Це різні величини. «Різниця
# світлоти помітна» не означає «ця світлота вам личить».
# Валідованого правила «людина → світлота основи» в корпусі НЕМА: тема-2 прямо
# каже, що зв'язок людина→сезон — неваліданована надбудова (R-CHEV-12), тоді
# як валідовані самі осі. Отже за правилом 4 (сила ≤ верифікація) світлота не
# має права нікого виключати. Вона рахується й ПОКАЗУЄТЬСЯ як факт («цей колір
# дасть перепад 68 L* до обличчя — це високий контраст»), а рішення лишається
# людині й моделі.
# ВІСЬ КОНТРАСТУ ПОВЕРНУЛАСЬ — АЛЕ НЕ ТА, ЯКУ Я ВИГАДУВАВ. Дві перші версії
# ("цільова відстань" і "зона") були моїм винаходом і обидві провалились на
# реальному профілі. Третя — прибрати світлоту зовсім — була ПОМИЛКОЮ ПРОТИ
# КОРПУСУ: я написав, що правила «людина → світлота» там нема, не дошукавшись.
# Воно є: K-CLR-02, з напрямком і двома різними рівнями сили, і K-CLR-01
# ставить контраст ПЕРШОЮ віссю за вагою, а не третьою.
# Тому вага контрасту тут — не з чипів Манселла (то перцептивна відстань, не
# придатність), а з порядку самого K-CLR-01: контраст > підтон > чистота.
# Числа лишаються тими самими, лише роль value віддано контрасту.
ЦІНА_КРОКУ = dict(контраст=8.02, hue=3.55, chroma=3.27)
_СУМА = sum(ЦІНА_КРОКУ.values())
ВАГА = {k: v / _СУМА for k, v in ЦІНА_КРОКУ.items()}

# Один крок Манселл-Value ≈ 10 одиниць L*. Використовується як масштаб
# насичення, а не як поріг: відхилення в один крок — половина балу, у два — нуль.
КРОК_V_L = 10.0
КРОК_C = 10.0          # ΔC=2 у Манселлі ≈ 10 одиниць C* CIELAB на цих чипах

# Цільова хрома основи за самозвітом про власні барви. T3: числа з практики,
# не з виміру. Названо явно, щоб потім калібрувати.
ЦІЛЬ_ХРОМИ = {"приглушені": 6.0, "яскраві": 22.0}
ЦІЛЬ_ХРОМИ_БЕЗ_ЗВІТУ = 12.0

_Ц_ПІДТ, _Р_ПІДТ = 57.0, 12.0     # центр і розкид осі підтону (colorspace)
# K-COL-06: C* < 12 — ахроматична сім'я, тону з неї не взяти. Та сама межа,
# що вже стоїть у міст.АХРОМАТИЧНА_МЕЖА; дублювати число не можна, тож воно
# тут одне й на обидва вжитки — і як «тон мовчить», і як «це нейтраль».
АХРОМАТИЧНА_МЕЖА = 12.0


def _тепло(h):
    """Та сама формула, що colorspace застосовує до шкіри, — до будь-якого тону.
    Одна вісь для людини й для тканини: інакше «тепле» означало б різне."""
    if h is None:
        return 0.0
    return max(-1.5, min(1.5, (h - _Ц_ПІДТ) / _Р_ПІДТ)) / 1.5


def _рампа(відхил, масштаб):
    """1 при нулі, 0.5 на одному кроці, 0 на двох. Неперервна, без порогів."""
    return max(0.0, 1.0 - abs(відхил) / (2.0 * масштаб))


def зона_світлоти(F, intent="conventional"):
    """ЛЮДИНА — ЗОНА В ПРОСТОРІ ЗНАЧЕНЬ, А НЕ ТОЧКА. Тут це буквально.

    ДРУГА ПОМИЛКА ЦІЄЇ ФУНКЦІЇ, ЗНОВУ ПІЙМАНА ВИМІРОМ, ЗНОВУ НА РЕАЛЬНОМУ
    ПРОФІЛІ. Попередня версія брала `value_gap` (перепад волосся↔шкіра) як
    ЦІЛЬОВУ ВІДСТАНЬ основи від шкіри. На світлій блондинці з фото це дало
    `цільовий_перепад = 0.5 L*`: її волосся (62.5 / 78.4 / 88.1, середнє 76.3)
    майже тотожне шкірі (75.8), тож перепад чесно виміряний як 0.5 — і правило
    вимагало вдягнути її в колір її ж обличчя. Наслідок на екрані: беж (L 74)
    діставав 0.78, а все інше валилось у 0.2–0.4, включно з тим, що вона сама
    обрала. Перепад людини — це вимір ЛЮДИНИ; перетворювати його на цільову
    відстань ТКАНИНИ від обличчя нічим не підперто, і я це вигадав.

    ЩО ЗАМІСТЬ. Зона світлоти особи = [min, max] по шкірі й УСІХ пасмах
    волосся. Основа всередині зони не сперечається з обличчям, бо така
    світлота на людині вже є. Поза зоною бал спадає за один крок Value.
    Це та сама архітектура, що й скрізь у проєкті: людина як ЗОНА в просторі
    значень, а не мітка. Ширина зони при цьому сама несе контраст — у
    низькоконтрастної вона вузька, у висококонтрастної широка, і додаткової
    константи не потрібно.

    ОЧІ НЕ ВХОДЯТЬ. Та сама підстава, що в `outfit.контраст_особи`: площа
    мала, і темні очі робили б попелясту блондинку темною.

    ПІД STATEMENT ЗОНА ШИРШАЄ на крок Value з кожного боку: мета не «лестити
    обличчю», і вихід за власну світлоту тут — інструмент, а не помилка.
    """
    L = []
    for k, v in (F or {}).items():
        if k.startswith("_") or not isinstance(v, dict):
            continue
        if k == "шкіра" or k.startswith("волосся"):
            if v.get("L") is not None:
                L.append(float(v["L"]))
    if not L:
        return 40.0, 80.0
    низ, верх = min(L), max(L)
    if (intent or "conventional") != "conventional":
        низ, верх = низ - КРОК_V_L, верх + КРОК_V_L
    return низ, верх


def _температура_людини(F, самозвіт, надійність):
    """Повертає (позиція ∈[−1,1], вага ∈[0,1], джерело).

    ДВІ ОРТОГОНАЛЬНІ ОСІ, як їх уже описує palette.температура: величина
    підтону й надійність виміру. Тут вони не гейт, а МНОЖНИК ваги — саме те,
    чого вимагає принцип неперервності. Самозвіт від карток біля обличчя б'є
    фото: корпус прямо каже, що при надійності 0.15 канон приписує питати.
    """
    сз = самозвіт or {}
    за_словом = {"золото": +0.8, "срібло": -0.8}.get(сз.get("метал"))
    н = {"теплі": +0.8, "холодні": -0.8}.get(сз.get("нейтраль"))
    б = {"теплий": +0.5, "холодний": -0.5}.get(сз.get("білий"))
    голоси = [x for x in (за_словом, н, б) if x is not None]
    if голоси:
        # Три картки — три голоси про одну вісь. Середнє, а не перший-ліпший:
        # людина може відповісти «золото» й «холодні нейтралі», і це не помилка,
        # а слабкий сигнал. Вага росте з кількістю узгоджених голосів.
        поз = sum(голоси) / len(голоси)
        згода = 1.0 - (max(голоси) - min(голоси)) / 2.0 if len(голоси) > 1 else 1.0
        return поз, max(0.25, min(1.0, abs(поз) * згода * (0.6 + 0.2 * len(голоси)))), \
            "самозвіт біля обличчя (%d голос(и))" % len(голоси)
    сила = ((F.get("шкіра") or {}).get("тепло_сила"))
    if сила is None:
        return 0.0, 0.0, "підтону нема"
    поз = max(-1.0, min(1.0, float(сила) / 1.5))
    return поз, abs(поз) * надійність, "фото (надійність %.2f)" % надійність


def ранг(F, ОСНОВИ, порядок, самозвіт=None, контраст=None, надійність=None,
         барви=None, intent="conventional", макіяж=None):
    """Неперервний ранг усіх основ під конкретну людину.

    ОСНОВИ  — {ключ: (hex, назва)}; порядок — список ключів.
    Повертає список dict(ключ, назва, hex, бал, чому, осі) за спаданням балу.
    """
    from colorspace import to_lab
    def lch(hx):
        hx = hx.lstrip("#")
        L, a, b = to_lab(tuple(int(hx[i:i + 2], 16) for i in (0, 2, 4)))
        return L, math.hypot(a, b), (math.degrees(math.atan2(b, a)) % 360)

    # ── НАДІЙНІСТЬ СТИСКАЄ СИГНАЛ ДО 0.5, А НЕ ВАГУ ДО НУЛЯ ──────────────
    # ПЕРША ВЕРСІЯ МНОЖИЛА ВАГУ НА НАДІЙНІСТЬ, І ЦЕ ТИХО ЛАМАЛО КОРПУС.
    # Виміряно: ваги виходили V=0.459 C=0.077 H=0.018, тобто світлота важила
    # 83% балу — тоді як тема-2 міряє 8.02 : 3.27 : 3.55, тобто 54%. Множення
    # на надійність (0.85 / 0.35 / 0.15) підмінило перцептивну ціну кроку
    # довірою до виміру: дві різні речі, зведені в одну цифру. Наслідок було
    # видно на екрані — ряд «рекомендовані» ставав просто смугою світлоти.
    # Правильно: ненадійна вісь не важить менше, вона МЕНШЕ ЗНАЄ. Її внесок
    # тягнеться до 0.5 (нема сигналу), а вага лишається корпусною. Тоді
    # співвідношення 2.45 : 1 : 1.09 виживає, а ненадійна вісь просто перестає
    # розрізняти — замість того, щоб перекошувати решту.
    н = надійність or {}
    r_v = float(н.get("contrast", 0.85))
    r_c = float(н.get("chroma", 0.35))
    r_u = float(н.get("undertone", 0.15))
    стиснути = lambda s, r: 0.5 + r * (s - 0.5)

    import face_contrast as KC
    шк = F.get("шкіра") or {}
    L_шк = float(шк.get("L") or 60.0)
    L_обл = KC.value_обличчя(F) or L_шк          # K-CLR-04: волосся важить 75%
    # L_обл передається, бо важіль макіяжу тепер МІРЯЄТЬСЯ від зони обличчя, а не
    # береться пласкою константою: нюдова помада й темна винна більше не однакові.
    ліміт, важіль = KC.дозволений_контраст(контраст, макіяж, L_обличчя=L_обл)
    дом = KC.домінантність(F, r_c)
    шт_нейтр, шт_чому = KC.штраф_нейтралі(дом, (контраст or {}).get("рівень"))

    ціль_C = ЦІЛЬ_ХРОМИ.get(барви, ЦІЛЬ_ХРОМИ_БЕЗ_ЗВІТУ)
    r_c_еф = 1.0 if барви in ЦІЛЬ_ХРОМИ else r_c
    поз_т, впевн_т, дж_т = _температура_людини(F, самозвіт, r_u)

    out = []
    for k in порядок:
        якщо = ОСНОВИ.get(k)
        if not якщо:
            continue
        hx, назва = якщо[0], якщо[1]
        L, C, h = lch(hx)
        # ── K-CLR-02: асиметричний контраст біля обличчя ─────────────────
        s_K, перепад, напрям = KC.бал_контрасту(L, L_обл, ліміт)
        s_K = стиснути(s_K, r_v)
        рівень = ("низький" if перепад < 22 else
                  "середній" if перепад < 45 else "високий")
        # ── вісь C ───────────────────────────────────────────────────────
        s_C = стиснути(_рампа(C - ціль_C, КРОК_C), r_c_еф)
        # ── вісь H: згода температур; на ахроматі тону нема, і вісь мовчить
        ахромат = C < АХРОМАТИЧНА_МЕЖА
        s_H = 0.5 if ахромат else стиснути(1.0 - abs(поз_т - _тепло(h)) / 2.0, впевн_т)
        бал = ВАГА["контраст"] * s_K + ВАГА["chroma"] * s_C + ВАГА["hue"] * s_H
        # Домінантність: чиста нейтраль для colour-домінантної низькоконтрастної
        # особи — саме те, від чого корпус застерігає прямо.
        if C < АХРОМАТИЧНА_МЕЖА and шт_нейтр:
            бал *= (1.0 - шт_нейтр)
        чому = []
        чому.append("перепад до обличчя %.0f L* (%s ваш контраст, ліміт %.0f) — %s"
                    % (перепад, напрям, ліміт, рівень))
        if C < АХРОМАТИЧНА_МЕЖА and шт_нейтр:
            чому.append("нейтраль знижена: %s" % шт_чому)
        if впевн_т > 0.1 and not ахромат:
            чому.append("температура %s" % ("збігається" if s_H > 0.7 else
                        "розходиться" if s_H < 0.4 else "нейтрально"))
        if r_c_еф > 0.5:
            чому.append("хрома %.0f проти цілі %.0f" % (C, ціль_C))
        out.append(dict(ключ=k, назва=назва, hex=hx, бал=round(бал, 3),
                        чому="; ".join(чому), перепад=round(перепад, 1), контраст=рівень,
                        осі=dict(K=round(s_K, 2), C=round(s_C, 2), H=round(s_H, 2),
                                 L=round(L, 1), Cstar=round(C, 1))))
    out.sort(key=lambda x: -x["бал"])
    # ── СЛІД: ЩО САМЕ СПРАЦЮВАЛО В ЦЬОМУ РАНЗІ ──────────────────────────
    # Доти ранг повертав поле `правило` РЯДКОМ ТЕКСТУ («K-CLR-02: перевищити…»),
    # і жоден споживач його не парсив: до виходу моста доходив бал, а не код.
    # Тут ті самі правила лишають слід ІЗ ЧИСЛОМ, на якому спрацювали.
    import trace as СЛ
    _перевищ = [x for x in out if x["осі"]["K"] < 0.85 and x["перепад"] > ліміт]
    if _перевищ:
        СЛ.запис("K-CLR-02", "перепад світлоти не той", "основи",
                 значення="перевищують ліміт %.0f L*: %d основ" % (ліміт, len(_перевищ)),
                 сила=round(1.0 - min(x["осі"]["K"] for x in _перевищ), 3),
                 напрям="перевищення (strong)")
    _недобір = [x for x in out if x["перепад"] < ліміт - 1.0]
    if _недобір:
        СЛ.запис("K-CLR-02", "перепад світлоти не той", "основи",
                 значення="недобирають до ліміту %.0f L*: %d основ" % (ліміт, len(_недобір)),
                 сила=round(1.0 - min(x["осі"]["K"] for x in _недобір), 3),
                 напрям="недобір (soft)")
    if шт_нейтр:
        СЛ.запис("K-CLR-02", "нейтралі гасять цю особу", "основи",
                 значення="штраф чистій нейтралі %.2f, домінантність %s (хрома рис %s)"
                          % (шт_нейтр, дом.get("рід"), дом.get("власна_хрома")),
                 сила=round(шт_нейтр, 3), напрям="домінантність [C·strong]")
    if L_обл != L_шк:
        СЛ.запис("K-CLR-04", "волосся визначає світлоту зони обличчя", "основи",
                 значення="L обличчя %.1f проти L шкіри %.1f (вага волосся %.2f)"
                          % (L_обл, L_шк, KC.ВАГА_ВОЛОССЯ), сила=KC.ВАГА_ВОЛОССЯ)
    if важіль:
        _д = важіль["Δ"] if isinstance(важіль, dict) else KC.ВАЖІЛЬ_МАКІЯЖУ_L
        _дж = важіль["джерело"] if isinstance(важіль, dict) else "константа T3"
        СЛ.запис("K-CLR-03", "макіяж піднімає доступний контраст", "основи",
                 значення="ліміт піднято на %.1f L* до %.1f (%s)" % (_д, ліміт, _дж),
                 сила=round(min(1.0, _д / KC.ВАЖІЛЬ_МАКІЯЖУ_L), 3))
    if впевн_т > 0.1:
        СЛ.запис("K-CLR-01", "вісь підтону бере участь у ранзі", "основи",
                 значення="позиція %.2f, впевненість %.2f, джерело %s"
                          % (поз_т, впевн_т, дж_т), сила=round(впевн_т, 2),
                 напрям="вісь 2 з трьох за спаданням ваги")
    підстав = True   # контраст рахується завжди: надійність value 0.85
    return out, dict(L_шкіри=round(L_шк, 1), L_обличчя=round(L_обл, 1),
                     ліміт_контрасту=round(ліміт, 1), важіль_макіяжу=важіль,
                     домінантність=дом, штраф_нейтралі=round(шт_нейтр, 3),
                     є_підстави=підстав,
                     нема_підстав=(None if підстав else
                     "самозвіту нема, а з фото надійність хроми 0.35 і підтону 0.15 — "
                     "ранжувати нема на чому. Ряди показані, але порядок у них "
                     "майже нічого не означає: заповніть картки біля обличчя."),
                     ціль_хроми=ціль_C, температура=dict(позиція=round(поз_т, 2),
                     впевненість=round(впевн_т, 2), джерело=дж_т),
                     ваги=dict(K=round(ВАГА["контраст"], 3), C=round(ВАГА["chroma"], 3),
                               H=round(ВАГА["hue"], 3)),
                     стиснення=dict(C=r_c_еф, H=round(впевн_т, 2),
                                    чому="надійність тягне вісь до 0.5, ваги корпусні"),
                     правило="K-CLR-02: перевищити контраст особи гірше (strong), "
                             "ніж недодати (soft); K-CLR-04: волосся важить 75%")


def за_родом(ранжовані):
    """Ділить ранг на НЕЙТРАЛІ й КОЛЬОРИ за K-COL-06 (C* < 12).

    ЧОМУ ЦЕ ОКРЕМИЙ ПОДІЛ, А НЕ ОДИН СПИСОК. На екрані ряд «рекомендовані»
    виходив суцільною смугою нейтралей — і питання «де тут рекомендовані
    КОЛЬОРИ» лишалось без відповіді, бо кольори стояли нижче, серед «інших»,
    поруч зі справді невдалими. Це не косметика: нейтраль і колір грають різні
    ролі — нейтраль іде в найбільшу річ, колір стає акцентом, — і ранжувати їх
    в одному списку означає порівнювати те, що не конкурує.
    """
    н = [x for x in ранжовані if x["осі"]["Cstar"] < АХРОМАТИЧНА_МЕЖА]
    к = [x for x in ранжовані if x["осі"]["Cstar"] >= АХРОМАТИЧНА_МЕЖА]
    return н, к


# ПІДЛОГА РЕКОМЕНДАЦІЇ. 0.5 — не кругле число з голови: кожна вісь віддає рівно
# 0.5, коли в неї нема сигналу (див. `стиснути`). Отже сумарний бал 0.5 означає
# «код не знає нічого», а нижче — «код має докази ПРОТИ». Називати таке
# «рекомендованим» не можна, скільки б воно не було першим у своїй групі.
# ЩО ЦЕ ПІЙМАЛО: на реальному профілі верхній колір групи мав 0.338 і стояв
# підписаний «рекомендовано».
ПІДЛОГА_РЕКОМЕНДАЦІЇ = 0.5


def поділ(ранжовані, мінімум=5, максимум=10):
    """Де кінчаються «рекомендовані».

    НЕ фіксована кількість: ріжеться по НАЙБІЛЬШОМУ розриву балу у вікні
    [мінімум, максимум]. Фіксоване «перші вісім» брехало б про те, що вісім
    кольорів справді підходять — на пласкому розподілі підходять усі, на
    крутому лише два.
    """
    ранжовані = [x for x in ранжовані if x["бал"] >= ПІДЛОГА_РЕКОМЕНДАЦІЇ]
    if len(ранжовані) <= мінімум:
        return len(ранжовані)
    хв = min(максимум, len(ранжовані) - 1)
    найкращий, де = -1.0, мінімум
    for i in range(мінімум, хв + 1):
        розрив = ранжовані[i - 1]["бал"] - ранжовані[i]["бал"]
        if розрив > найкращий:
            найкращий, де = розрив, i
    return де
