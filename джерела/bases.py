# ТРЕТЯ ВЕРСІЯ ЦІЄЇ ОСІ, І ЦЬОГО РАЗУ ЇЇ ПРОСТО НЕМА В БАЛІ.
# Дві попередні були неправильні, обидві піймані на реальному профілі:
#   (1) `value_gap` як цільова відстань → на світлій блондинці ціль вийшла
