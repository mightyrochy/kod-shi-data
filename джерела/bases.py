# має права нікого виключати. Вона рахується й ПОКАЗУЄТЬСЯ як факт («цей колір
# дасть перепад 68 L* до обличчя — це високий контраст»), а рішення лишається
# людині й моделі.
# ВІСЬ КОНТРАСТУ ПОВЕРНУЛАСЬ — АЛЕ НЕ ТА, ЯКУ Я ВИГАДУВАВ. Дві перші версії
