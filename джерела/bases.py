# ту саму 12.
АХРОМАТИЧНА_МЕЖА = float(_РЕЄСТР.C["neutral_C"])


def _бік_тону(h):
    """Температура ТКАНИНИ за знаком b*: sin(h) ∈ [−1, 1], +1 — найтепліше
    (жовтий, 90°), −1 — найхолодніше (синій, 270°), 0 — червоний / ціан.

    ЧОМУ НЕ ФОРМУЛА ШКІРИ. Доти тут стояла копія `colorspace`-осі підтону
    шкіри — (h − 57°)/12°, обрізана на ±1.5. Вона має сенс лише у вікні
    39–75°, де живе тон шкіри; для тканини все понад 75° (жовтий, зелений,
    СИНІЙ, фіолетовий, маджента) читалось як «+1, тепле», а все нижче 39°
    (червоний, кораловий) — як «−1, холодне». Виміряно на стенд_вх з картками
    «срібло / холодні нейтралі / холодний білий»: перший рекомендований колір —
    персиковий (h 30°), а блакитний і бузковий діставали s_H 0.25. Вісь оживала
    від карток і працювала НАВПАКИ.
    Знак b* — та сама конвенція, якою система вже ділить тканину: ґратка основ
    підписує «тепла» при 0 ≤ h < 180 (`bridge._ґратка_основ`), нейтралі
    людини — по b* (`реєстр_правил.C["b_нейтралі"]`, K-COL-06)."""
    if h is None:
        return 0.0
    return math.sin(math.radians(h))


def _відхил_тону_ΔE(lab, поз):
    """ΔE00 від кольору до найближчого кольору НА БОЦІ температури людини.

    Бік — знак `поз` (тепла > 0, холодна < 0). Колір на тому ж боці або на межі
    (b* = 0) — відхил 0. Колір на протилежному боці повертається по тону до
    ближчої межі (0° або 180°) при тій самій світлоті й хромі, і відстань —
    ΔE00 цього повороту. Отже насичений синій для теплої людини — далеко,
    приглушений сіро-синій — близько, а нижче АХРОМАТИЧНА_МЕЖА вісь мовчить
    (K-COL-06) ще до цього виклику. Ціль — не «тон, рівний теплу людини»:
    тепла людина не має карати жовтий за те, що він тепліший за неї."""
    L, a, b = lab
    C = math.hypot(a, b)
    if C <= 0.0 or поз == 0.0:
        return 0.0
    h = math.degrees(math.atan2(b, a)) % 360
    бік = math.copysign(1.0, поз)
    if _бік_тону(h) * бік >= 0.0:
        return 0.0
    # до 0° — через менший кут; до 180° — через менший кут
    до_0 = min(h, 360.0 - h)
    до_180 = abs(h - 180.0)
    межа = 0.0 if до_0 <= до_180 else 180.0
    return _cs.de00((L, a, b), (L, C * math.cos(math.radians(межа)),
                                C * math.sin(math.radians(межа))))


def _відхил_хроми_ΔE(lab, ціль_C):
    """ΔE00 від кольору до того самого кольору на цільовій хромі (той самий
    тон і світлота). Для ахромату (C = 0) ціль береться по осі a*."""
    L, a, b = lab
    C = math.hypot(a, b)
    if C <= 0.0:
        return _cs.de00((L, a, b), (L, float(ціль_C), 0.0))
    k = float(ціль_C) / C
    return _cs.de00((L, a, b), (L, a * k, b * k))


def _рампа(відхил, масштаб):
    """1 при нулі, 0.5 на одному кроці, 0 на двох. Неперервна, без порогів.
    Масштаб у ранзі один на всі осі — КРОК_ΔE, і відхил тоді в ΔE00."""
    return max(0.0, 1.0 - abs(відхил) / (2.0 * масштаб))


# `зона_світлоти` → лабораторія/без_викликача.py (Н-02-02: ДОСЯЖНІСТЬ 13.09 — «ніхто»)


def _температура_людини(F, самозвіт, надійність):
    """Повертає (позиція ∈[−1,1], вага ∈[0,1], джерело).

    ДВІ ОРТОГОНАЛЬНІ ОСІ, як їх уже описує palette.температура: величина
    сигналу й надійність виміру. Тут вони не гейт, а МНОЖНИК ваги — саме те,
    чого вимагає принцип неперервності. Самозвіт від карток біля обличчя б'є
    все: корпус прямо каже, що канон приписує питати. Без карток знак і сила —
    з b* ОЧЕЙ (тема-2 §6.1, K-COND-02), не з підтону шкіри; `надійність` —
    словник осей джерела (`colorspace.reliability`), з якого береться `hue`
    лише для очей з фото.
    """
    сз = самозвіт or {}
    за_словом = {"золото": +0.8, "срібло": -0.8}.get(сз.get("метал"))
    н = {"теплі": +0.8, "холодні": -0.8}.get(сз.get("нейтраль"))
    б = {"теплий": +0.5, "холодний": -0.5}.get(сз.get("білий"))
    голоси = [x for x in (за_словом, н, б) if x is not None]
    if голоси:
        # Три картки — три голоси про одну вісь. Середнє, а не перший-ліпший:
        # людина може відповісти «золото» й «холодні нейтралі», і це не помилка,
        # а слабкий сигнал. Вага росте з кількістю узгоджених голосів.
        поз = sum(голоси) / len(голоси)
        згода = 1.0 - (max(голоси) - min(голоси)) / 2.0 if len(голоси) > 1 else 1.0
        return поз, max(0.25, min(1.0, abs(поз) * згода * (0.6 + 0.2 * len(голоси)))), \
            "самозвіт біля обличчя (%d голос(и))" % len(голоси)
    # ── БЕЗ КАРТОК: ЗНАК І СИЛА — З b* ОЧЕЙ, НЕ З ПІДТОНУ ШКІРИ (20.09.2026) ──
    # Рішення власника: «якщо база знань каже, що колір очей важливий, значить
    # всі правила потрібно застосовувати». Корпус: тема-2 §6.1 (:1712), Perrett
    # 2023 — вибір одягу йде за ОЧИМА; зміна меланіну шкіри при тих самих очах
    # вибору не рухає (K-COND-02). Доти тут стояв фолбек на `шкіра.тепло_сила`
    # (надійність 0.15): виміряно (рядки 60, 81 дошки) — внесок осі ±0.001, вісь
    # мовчала, і засмага (зсув L*/b* шкіри в межах однієї людини) могла б її
    # перемкнути, чого корпус забороняє. Тепер:
    #   ЗНАК  — той самий свідок, що R-COL-16 у пулі й суді
    #           (`палітра_нейтраль.бік_b_проти_людини`, межі `b_нейтралі`), не другий;
    #   СИЛА  — |b* очей| за межею боку, лінійно до 1 на `C["b_очей_повна"]` (T3);
    #   ВПЕВНЕНІСТЬ — сила × надійність джерела очей: hex-ввід повна, фото —
    #           `надійність["hue"]` (K-PC-05, як personal_palette для акцентів від очей);
    #   ITA/підтон шкіри знаком не є і запасним ключем не стає (K-COND-02);
    #   очі в ахроматичній смузі або їх нема → внесок 0, як і доти без підтону.
    # Вага 0.24, рампа, `_бік_тону` і ґратка не змінені: інше лише джерело.
    from палітра_нейтраль import бік_b_проти_людини
    бб = бік_b_проти_людини(F)
    if not бб.get("вхід"):
        return 0.0, 0.0, "очі: %s — внесок 0" % бб.get("чому")
    межа = бб["межі"]["теплий_від"] if бб["бік"] > 0 else бб["межі"]["холодний_до"]
    сила = min(1.0, abs(float(бб["b_очей"]) - float(межа)) / float(_РЕЄСТР.C["b_очей_повна"]))
    з_фото = bool((F.get("_meta") or {}).get("from_photo"))
    над = float((надійність or {}).get("hue", 0.35)) if з_фото else 1.0
    поз = float(бб["бік"]) * сила
    return поз, сила * над, ("b* очей %.1f — %s бік (сила %.2f, %s)"
                             % (бб["b_очей"], "теплий" if бб["бік"] > 0 else "холодний", сила,
                                "з фото, надійність тону %.2f" % над if з_фото else "hex-ввід, надійність повна"))


def ранг(F, ОСНОВИ, порядок, самозвіт=None, контраст=None, надійність=None,
         барви=None, _intent="conventional", макіяж=None):
    """Неперервний ранг усіх основ під конкретну людину.

    ОСНОВИ  — {ключ: (hex, назва)}; порядок — список ключів.
    Повертає список dict(ключ, назва, hex, бал, чому, осі) за спаданням балу.

    `_intent` НЕ ЧИТАЄТЬСЯ СВІДОМО (рядок 106 дошки, 20.09.2026). Викликач
    (`міст_основи._основи`) передає намір із профілю — той самий, що йде в палітру
    акцентів і композитор, — але правила «намір → добір ОСНОВ» у корпусі нема.
    K-PER-00 і «всі мапи умовні на intent» стоять у темі-4 (:721, :223) і
    перемикають мапи ТІЛА (частина V); у темі-2 намір гейтує лише прийоми НАД
    палітрою — K-PAL-07 колір-блок (:1853), K-PAL-12 драматизація м'якої палітри
    (:1858, `palettes.ПРИЙОМИ`) — і анти-правило помади (:1475), а осі цього рангу
    (K-CLR-01/02, K-CLR-04, K-COL-06, R-COL-16, K-COND-02) записані без наміру;
    «мета» R-CHEV-08 (:1030) — це «підсилити / приглушити відтінок», і її вже
    читає `palette.температура`. Єдиний свідок у коді — `зона_світлоти(F, intent)`
    у `лабораторія/без_викликача.py` (розширює зону на крок Value під будь-яким
    не-conventional наміром) — і це та сама «зона [min, max] як умова», яку
    заголовок цього модуля називає власним винаходом, що провалився на реальному
    профілі (чорний і нейві «за межами»). Тому намір тут — страховка спільної
    сигнатури `_основи`, не прогалина: дописати вісь з голови означало б вигадати
    правило (правило 4: сила ≤ верифікація). Виміряно (`проби/bas_namir_106.py`):
    на профілі стенда всі шість намірів `реєстр_намір.INTENT` дають одну й ту
    саму вісімку чипів, max |Δбал| 0.
    """
    from colorspace import to_lab
    def лаб(hx):
        """Lab із «#rrggbb» чипа основи."""
        hx = hx.lstrip("#")
        return to_lab(tuple(int(hx[i:i + 2], 16) for i in (0, 2, 4)))

    # ── НАДІЙНІСТЬ СТИСКАЄ СИГНАЛ ДО 0.5, А НЕ ВАГУ ДО НУЛЯ ──────────────
    # ПЕРША ВЕРСІЯ МНОЖИЛА ВАГУ НА НАДІЙНІСТЬ, І ЦЕ ТИХО ЛАМАЛО КОРПУС.
    # Виміряно: ваги виходили V=0.459 C=0.077 H=0.018, тобто світлота важила
    # 83% балу — тоді як тема-2 міряє 8.02 : 3.27 : 3.55, тобто 54%. Множення
    # на надійність (0.85 / 0.35 / 0.15) підмінило перцептивну ціну кроку
    # довірою до виміру: дві різні речі, зведені в одну цифру. Наслідок було
    # видно на екрані — ряд «рекомендовані» ставав просто смугою світлоти.
    # Правильно: ненадійна вісь не важить менше, вона МЕНШЕ ЗНАЄ. Її внесок
    # тягнеться до 0.5 (нема сигналу), а вага лишається корпусною. Тоді
    # співвідношення 2.45 : 1 : 1.09 виживає, а ненадійна вісь просто перестає
    # розрізняти — замість того, щоб перекошувати решту.
    н = надійність or {}
    r_v = float(н.get("contrast", 0.85))
    r_c = float(н.get("chroma", 0.35))
    # `undertone` (0.15) тут більше не читається: вісь H бере знак і силу з очей
    # (`_температура_людини`), а надійність тону з фото — `н["hue"]` (K-COND-02).
    стиснути = lambda s, r: 0.5 + r * (s - 0.5)

    import face_contrast as KC
    шк = F.get("шкіра") or {}
    L_шк = float(шк.get("L") or 60.0)
    L_обл = KC.value_обличчя(F) or L_шк          # K-CLR-04: волосся важить 75%
    # L_обл передається, бо важіль макіяжу тепер МІРЯЄТЬСЯ від зони обличчя, а не
    # береться пласкою константою: нюдова помада й темна винна більше не однакові.
    # `макіяж=None` → функція бере слід із самої особи (`контраст["макіяж"]`,
    # який кладе `outfit.контраст_особи`): один ліміт на ранг, вікно і суд.
    ліміт, важіль = KC.дозволений_контраст(контраст, макіяж, L_обличчя=L_обл)
    дно = (ліміт - float(важіль["Δ"])) if важіль else None   # важіль піднімає стелю, не дно
    дом = KC.домінантність(F, r_c)
    шт_нейтр, шт_чому = KC.штраф_нейтралі(дом, (контраст or {}).get("рівень"))

    ціль_C = ЦІЛЬ_ХРОМИ.get(барви, ЦІЛЬ_ХРОМИ_БЕЗ_ЗВІТУ)
    r_c_еф = 1.0 if барви in ЦІЛЬ_ХРОМИ else r_c
    поз_т, впевн_т, дж_т = _температура_людини(F, самозвіт, н)

    out = []
    for k in порядок:
        якщо = ОСНОВИ.get(k)
        if not якщо:
            continue
        hx, назва = якщо[0], якщо[1]
        lab = лаб(hx)
        L, C = lab[0], math.hypot(lab[1], lab[2])
        # ── K-CLR-02: асиметричний контраст біля обличчя (відхил у ΔE00);
        #    дно — власний контраст, стеля — ліміт з важелем макіяжу ──────
        s_K, перепад, напрям = KC.бал_контрасту(lab, L_обл, ліміт, КРОК_ΔE, дно=дно)
        s_K = стиснути(s_K, r_v)
        рівень = ("низький" if перепад < 22 else
                  "середній" if перепад < 45 else "високий")
        # ── вісь C: ΔE00 до цільової хроми, та сама рампа ─────────────────
        s_C = стиснути(_рампа(_відхил_хроми_ΔE(lab, ціль_C), КРОК_ΔE), r_c_еф)
        # ── вісь H: ΔE00 до боку температури людини; на ахроматі тону нема,
        #    і вісь мовчить (K-COL-06)
        ахромат = C < АХРОМАТИЧНА_МЕЖА
        s_H = 0.5 if ахромат else стиснути(
            _рампа(_відхил_тону_ΔE(lab, поз_т), КРОК_ΔE), впевн_т)
        бал = ВАГА["контраст"] * s_K + ВАГА["chroma"] * s_C + ВАГА["hue"] * s_H
        # Домінантність: чиста нейтраль для colour-домінантної низькоконтрастної
        # особи — саме те, від чого корпус застерігає прямо.
        if C < АХРОМАТИЧНА_МЕЖА and шт_нейтр:
            бал *= (1.0 - шт_нейтр)
        чому = []
        чому.append("перепад до обличчя %.0f L* (%s ваш контраст, ліміт %.0f%s) — %s"
                    % (перепад, напрям, ліміт,
                       (" з них +%.0f від макіяжу" % важіль["Δ"]) if важіль else "", рівень))
        if C < АХРОМАТИЧНА_МЕЖА and шт_нейтр:
            чому.append("нейтраль знижена: %s" % шт_чому)
        if впевн_т > 0.1 and not ахромат:
            чому.append("температура %s" % ("збігається" if s_H > 0.7 else
                        "розходиться" if s_H < 0.4 else "нейтрально"))
        if r_c_еф > 0.5:
            чому.append("хрома %.0f проти цілі %.0f" % (C, ціль_C))
        out.append(dict(ключ=k, назва=назва, hex=hx, бал=round(бал, 3),
                        чому="; ".join(чому), перепад=round(перепад, 1), контраст=рівень,
                        осі=dict(K=round(s_K, 2), C=round(s_C, 2), H=round(s_H, 2),
                                 L=round(L, 1), Cstar=round(C, 1))))
    out.sort(key=lambda x: -x["бал"])
    # ── СЛІД: ЩО САМЕ СПРАЦЮВАЛО В ЦЬОМУ РАНЗІ ──────────────────────────
    # Доти ранг повертав поле `правило` РЯДКОМ ТЕКСТУ («K-CLR-02: перевищити…»),
    # і жоден споживач його не парсив: до виходу моста доходив бал, а не код.
    # Тут ті самі правила лишають слід ІЗ ЧИСЛОМ, на якому спрацювали.
    import trace as СЛ
    _перевищ = [x for x in out if x["осі"]["K"] < 0.85 and x["перепад"] > ліміт]
    if _перевищ:
        СЛ.запис("K-CLR-02", "перепад світлоти не той", "основи",
                 значення="перевищують ліміт %.0f L*: %d основ" % (ліміт, len(_перевищ)),
                 сила=round(1.0 - min(x["осі"]["K"] for x in _перевищ), 3),
                 напрям="перевищення (strong)")
    _недобір = [x for x in out if x["перепад"] < (ліміт if дно is None else дно) - 1.0]
    if _недобір:
        СЛ.запис("K-CLR-02", "перепад світлоти не той", "основи",
                 значення="недобирають до ліміту %.0f L*: %d основ" % (ліміт, len(_недобір)),
                 сила=round(1.0 - min(x["осі"]["K"] for x in _недобір), 3),
                 напрям="недобір (soft)")
    if шт_нейтр:
        СЛ.запис("K-CLR-02", "нейтралі гасять цю особу", "основи",
                 значення="штраф чистій нейтралі %.2f, домінантність %s (хрома рис %s)"
                          % (шт_нейтр, дом.get("рід"), дом.get("власна_хрома")),
                 сила=round(шт_нейтр, 3), напрям="домінантність [C·strong]")
    if L_обл != L_шк:
        СЛ.запис("K-CLR-04", "волосся визначає світлоту зони обличчя", "основи",
                 значення="L обличчя %.1f проти L шкіри %.1f (вага волосся %.2f)"
                          % (L_обл, L_шк, KC.ВАГА_ВОЛОССЯ), сила=KC.ВАГА_ВОЛОССЯ)
    if важіль:
        _д = важіль["Δ"] if isinstance(важіль, dict) else KC.ВАЖІЛЬ_МАКІЯЖУ_L
        _дж = важіль["джерело"] if isinstance(важіль, dict) else "константа T3"
        СЛ.запис("K-CLR-03", "макіяж піднімає доступний контраст", "основи",
                 значення="ліміт піднято на %.1f L* до %.1f (%s)" % (_д, ліміт, _дж),
                 сила=round(min(1.0, _д / KC.ВАЖІЛЬ_МАКІЯЖУ_L), 3))
    if впевн_т > 0.1:
        СЛ.запис("K-CLR-01", "вісь підтону бере участь у ранзі", "основи",
                 значення="позиція %.2f, впевненість %.2f, джерело %s"
                          % (поз_т, впевн_т, дж_т), сила=round(впевн_т, 2),
                 напрям="вісь 2 з трьох за спаданням ваги")
    return out, dict(L_шкіри=round(L_шк, 1), L_обличчя=round(L_обл, 1),
                     ліміт_контрасту=round(ліміт, 1), важіль_макіяжу=важіль,
                     домінантність=дом, штраф_нейтралі=round(шт_нейтр, 3),
                     # ── ЩО САМЕ РАНЖУЄ, ВИМІРЯНО НА ЖИВІЙ ҐРАТЦІ ─────────────
                     # Тут стояли `є_підстави=True` (зашите) і `нема_підстав`,
                     # яке через це не могло вийти НІКОЛИ. Не читав жоден
                     # споживач — ні python, ні показ. Замість мертвого
                     # прапорця — виміряний внесок кожної осі: на 116 основах
                     # ґратки розкид балу по осях виходить
                     #     контраст ±0.102 · хрома ±0.025 · підтон ±0.001,
                     # тобто підтон, який K-CLR-01 ставить ДРУГОЮ віссю, у
                     # ранзі стократно слабший за першу й на порядок слабший
                     # за третю. Це не помилка ваг (вони корпусні, 0.54/0.22/
                     # 0.239), а наслідок стиснення надійністю 0.15: вісь не
                     # важить менше, вона нічого не знає. Хай це буде видно.
                     внесок_осей=dict(
                         контраст="вісь несе ранг (надійність value 0.85)",
                         хрома=("ціль зі слова людини" if r_c_еф > 0.5 else
                                "стиснена надійністю 0.35 — розрізняє слабко"),
                         підтон=("зі самозвіту біля обличчя" if дж_т.startswith("самозвіт") else
                                 "з b* очей (тема-2 §6.1, K-COND-02): %s — впевненість %.2f"
                                 % (дж_т, впевн_т) if впевн_т > 0.0 else
                                 "%s — вісь мовчить (0.5 на всіх кольорах). Знімається "
                                 "картками золото/срібло, теплий/холодний білий" % дж_т)),
                     ціль_хроми=ціль_C, температура=dict(позиція=round(поз_т, 2),
                     впевненість=round(впевн_т, 2), джерело=дж_т),
                     ваги=dict(K=round(ВАГА["контраст"], 3), C=round(ВАГА["chroma"], 3),
                               H=round(ВАГА["hue"], 3)),
                     стиснення=dict(C=r_c_еф, H=round(впевн_т, 2),
                                    чому="надійність тягне вісь до 0.5, ваги корпусні"),
                     # ── ЧУТЛИВІСТЬ БАЛА НА 1 ΔE00 ПО ОСІ — ЧИСЛОМ, НЕ ОБІЦЯНКОЮ ──
                     # Одна рампа на всі осі, тож Δбал/ΔE00 = ВАГА/(2·КРОК_ΔE) ×
                     # стиснення осі. `заявлено` — те саме без стиснення: саме
                     # це має збігатися з ЦІНА_КРОКУ (проба rang_ваги_осей.py).
                     чутливість_ΔE00=dict(
                         контраст_перевищення=round(ВАГА["контраст"] * r_v / (2 * КРОК_ΔE), 4),
                         контраст_недобір=round(ВАГА["контраст"] * r_v * KC.ШТРАФ_НЕДОБОРУ
                                                / KC.ШТРАФ_ПЕРЕВИЩЕННЯ / (2 * КРОК_ΔE), 4),
                         хрома=round(ВАГА["chroma"] * r_c_еф / (2 * КРОК_ΔE), 4),
                         тон=round(ВАГА["hue"] * впевн_т / (2 * КРОК_ΔE), 4),
                         крок_ΔE00=КРОК_ΔE,
                         заявлено=dict(контраст=round(ВАГА["контраст"] / (2 * КРОК_ΔE), 4),
                                       хрома=round(ВАГА["chroma"] / (2 * КРОК_ΔE), 4),
                                       тон=round(ВАГА["hue"] / (2 * КРОК_ΔE), 4))),
                     правило="K-CLR-02: перевищити контраст особи гірше (strong), "
                             "ніж недодати (soft); K-CLR-04: волосся важить 75%")


def за_родом(ранжовані):
    """Ділить ранг на НЕЙТРАЛІ й КОЛЬОРИ за K-COL-06 (C* < 12).

    ЧОМУ ЦЕ ОКРЕМИЙ ПОДІЛ, А НЕ ОДИН СПИСОК. На екрані ряд «рекомендовані»
    виходив суцільною смугою нейтралей — і питання «де тут рекомендовані
    КОЛЬОРИ» лишалось без відповіді, бо кольори стояли нижче, серед «інших»,
    поруч зі справді невдалими. Це не косметика: нейтраль і колір грають різні
    ролі — нейтраль іде в найбільшу річ, колір стає акцентом, — і ранжувати їх
    в одному списку означає порівнювати те, що не конкурує.
    """
    н = [x for x in ранжовані if x["осі"]["Cstar"] < АХРОМАТИЧНА_МЕЖА]
    к = [x for x in ранжовані if x["осі"]["Cstar"] >= АХРОМАТИЧНА_МЕЖА]
    return н, к


# ПІДЛОГА РЕКОМЕНДАЦІЇ. 0.5 — не кругле число з голови: кожна вісь віддає рівно
# 0.5, коли в неї нема сигналу (див. `стиснути`). Отже сумарний бал 0.5 означає
# «код не знає нічого», а нижче — «код має докази ПРОТИ». Називати таке
# «рекомендованим» не можна, скільки б воно не було першим у своїй групі.
# ЩО ЦЕ ПІЙМАЛО: на реальному профілі верхній колір групи мав 0.338 і стояв
# підписаний «рекомендовано».
ПІДЛОГА_РЕКОМЕНДАЦІЇ = 0.5


def поділ(ранжовані, мінімум=5, максимум=10):
    """Де кінчаються «рекомендовані».

    НЕ фіксована кількість: ріжеться по НАЙБІЛЬШОМУ розриву балу у вікні
    [мінімум, максимум]. Фіксоване «перші вісім» брехало б про те, що вісім
    кольорів справді підходять — на пласкому розподілі підходять усі, на
    крутому лише два.
    """
    ранжовані = [x for x in ранжовані if x["бал"] >= ПІДЛОГА_РЕКОМЕНДАЦІЇ]
    if len(ранжовані) <= мінімум:
        return len(ранжовані)
    хв = min(максимум, len(ранжовані) - 1)
    найкращий, де = -1.0, мінімум
    for i in range(мінімум, хв + 1):
        розрив = ранжовані[i - 1]["бал"] - ранжовані[i]["бал"]
        if розрив > найкращий:
            найкращий, де = розрив, i
    return де
