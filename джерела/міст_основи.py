# ЩО БУЛО. Двадцять два рядки з hex, зашитих руками, без джерела й без T-мітки.
# Аудит на повному каталозі показав, що вони випадкові в ОБИДВА боки:
#   · дев'ять пар ближчі за ΔE00 10 (нейві/темно-синій 3.1, коричневий/шоколад
