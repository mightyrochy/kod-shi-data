def _тон_від_рис_назовні(п):
    """Дуги тону, виведені з РИС людини, у формі, придатній для шару пояснень.

    ЧОМУ ЦЕ ТУТ ЗʼЯВИЛОСЬ. `gate_reach` рахував R-CHEV-14 як «спрацювало й лягло
    в пакет, але МІСТ НЕ ВІДДАЄ». Виміряно: у виході `палітри` було 5 кодів
    правил, і жодного з тонової осі. Тобто вся вісь — дуги на кожну рису, тиск
    індукції, перегуки, утримання K-PC-05 і виключення K-MUA-01 — рахувалась і
    вмирала на межі. Наслідок не в логах: шар ШІ, який пише жінці пояснення,
    НЕ МАВ ДОСТУПУ до тонової осі взагалі й не міг послатись на неї, навіть якби
    хотів. «Код + ші як одне ціле» на цій осі не існувало.

    Віддається саме те, що потрібно для пояснення й для перевірки, і нічого
    зайвого: яка риса, яка дуга, ДАНА чи ОБРАНА, з якою силою індукції, що
    утримано і чому, які кольори виключені й яким правилом."""
    спец_дж = None
    for г in (п.get("палітри", {}).get("розвилка") or []):
        if (г.get("спец") or {}).get("тон_від_рис"):
            спец_дж = г["спец"]["тон_від_рис"]; break
    if not спец_дж:
        return None
    риси = []
    for імʼя, дані in (спец_дж.get("риси") or {}).items():
        дуги = [dict(від=round(d["дуга"][0], 1), до=round(d["дуга"][1], 1),
                     тиск=d.get("тиск_центр"))
                for d in (дані.get("дуги") or [])]
        риси.append(dict(риса=імʼя, зона=дані.get("зона"),
                         рід=дані.get("рід"), h=дані.get("h"),
                         дуги=дуги, чому_нема=дані.get("чому_нема")))
    return dict(
        придатно=спец_дж.get("придатно"),
        утримано=спец_дж.get("утримано"),
        відношення=спец_дж.get("відношення"),
        h_шкіри=спец_дж.get("h_шкіри"),
        риси=риси,
        перегуки=[dict(риси=list(pp.get("риси") or []),
                       Δтемпература=pp.get("Δтемпература"))
                  for pp in (спец_дж.get("перегуки") or [])],
        напруги=[dict(риси=list(pp.get("риси") or []), суть=pp.get("суть"))
                 for pp in (спец_дж.get("напруги") or [])],
        правила=["R-CHEV-14", "K-PC-05"] + (["K-MUA-01"] if any(
            r.get("рід") == "обрана" for r in риси) else []),
        статус=спец_дж.get("статус"))


def палітри(вхід):
    """Законні схеми — зразками кольору, не числами. Людина закриває розвилку
    сама: код не має чим ранжувати гілки, і вдавати, що має, було б брехнею.

    Зразок кожного слота тепер береться З ДУГИ ТОНУ, яку задала схема, а не з
    двох сталих кутів. Через це «тональна» і «аналогова» перестали виглядати
    однаково — вони й не однакові, це малювання їх зрівнювало."""
    СЛ.почати()
    d = _json.loads(вхід) if isinstance(вхід, str) else вхід
    d = _нормалізувати_вхід(d)
    якір = _якір(d)
    намір = d.get("намір") or "conventional"
    F, T, зріст, kw = _збірка(d)
    вибір_вх = dict(d.get("вибір_кольору") or {})
    # ── БАЗА ЗА ЗАМОВЧУВАННЯМ = ПЕРША РЕКОМЕНДОВАНА ─────────────────────
    # Виміряно: поки база не обрана, всі схеми стоять на одному сталому якорі
    # й сходяться в одне. На тому самому профілі «тональна» й «аналогова»
    # давали 3 однакові слоти з 4 і ΔE00 сер 1.6 — тобто нижче за поріг
    # помітності, дві «різні» схеми були однією. Щойно база задана, ті самі
    # дві схеми розходяться на ΔE00 сер 8.7 (макс 18.5).
    # Тому мовчазний дефолт — не сталий якір, а верх рангу основ. Людина
    # бачить не чотири однакові смуги, а чотири різні, і може переобрати базу.
    if not вибір_вх.get("база_hex"):
        _о = _основи(F, самозвіт=d.get("самозвіт"), intent=намір,
                     макіяж=(d.get("сценарій") or {}).get("макіяж"))
        _топ = (_о.get("рекомендовані") or [None])[0]
        if _топ:
            # ТА САМА МЕЖА, ЩО ДІЛИТЬ РЯД (19.09.2026). Стояло `< 8`, тоді як
            # `bases.за_родом` ділить на «нейтралі»/«кольори» по 12 (реєстр
            # `neutral_C`, K-COL-06) і показ підписує чип «нейтраль» по 12. Три
            # місця, дві межі: клітинка з C* 8–12 лежала в ряду «нейтралі», а
            # тут типувалась «колір» і в `_якір_осн` ставала hue-якорем усіх
            # схем. Число читається з реєстру через `bases`, як і в `_основи`.
            import bases as _ОС
            вибір_вх.update(база=_топ["ключ"], база_hex=_топ["hex"],
                            база_тип=("нейтраль" if _топ["осі"]["Cstar"] < _ОС.АХРОМАТИЧНА_МЕЖА
                                      else "колір"),
                            база_за_замовчуванням=True)
    п = _пакет(F, T, зріст, kw, якір, намір, d.get("самозвіт"), вибір_вх, d.get("драп"))
    if not п.get("готово"):
        return _json.dumps(dict(помилка=п.get("чому")), ensure_ascii=False)
    гілки = []
    вибір = вибір_вх
    base_hex = вибір.get("база_hex")
    base_kind = вибір.get("база_тип")
    for i, г in enumerate(п["палітри"]["розвилка"]):
        # Гілки-концепти (контраст-мисматч) приходять БЕЗ спец: palette свідомо не
        # фабрикує їм фільтр. Раніше цей рядок падав на них; мовчки викидати теж
        # не можна — тоді «законних схем 4» було б неправдою. Тому вони їдуть із
        # міткою «не реалізовано як фільтр» і вибрати їх не можна.
        спец = (г.get("спец") or {}).get("слоти")
        if not спец:
            гілки.append(dict(і=i, схема=г["схема"], вага=г.get("вага"), коли=г.get("коли"),
                              застереження=г.get("застереження"), ролі=[], тон_вільний=0,
                              реалізована=False))
            continue
        сл = спец
        ролі, вільних = [], 0
        for ім in СЛОТИ:
            v = сл.get(ім)
            if not v or not v.get("L"):
                continue
            # ЗРАЗОК МУСИТЬ ПОКАЗУВАТИ ТЕ, ЩО ПІДЕ В ПРОМПТ. Виміряно:
            # `бриф.колір_слота` домножує хрому на НАСИЧЕНІСТЬ[вибір], а сюди
            # множник не передавався — тож вибір «приглушені / середні /
            # насичені» не міняв зразки НІ НА ОДИН БАЙТ (C* сер 46.0 у всіх
            # трьох). Людина тисне кнопку, бачить ті самі кольори й вирішує,
            # що кнопка мертва; а в промпт тим часом їде інша хрома.
            # Показане й надіслане мусять бути одним.
            v = dict(v, _насиченість=Б.НАСИЧЕНІСТЬ.get(
                вибір.get("насиченість") or "середні", 1.0))
            hx, вільний = Б.колір_слота(v)
            # Якщо користувач вибрав НЕЙТРАЛЬНУ основу, саме вона має
            # залишатися видимою основою палітри — але ЛИШЕ там, де слот сам
            # нейтрального тону («сім_я» від специфікації, K-COL-06). Раніше
            # перша умова спрацьовувала на ІМ'Я ролі «домінанта» саму по собі —
            # і в «тональна»/«аналогова»/«приглушена_комплементарна», де
            # домінанта несе КОЛІР схеми (той самий тон, що секундант і акцент),
            # обрана основа підмінювала його кольором, розсинхронізованим зі
            # смугами тієї самої гілки (рядок 50 БЕКЛОГ: «тональна» показувала
            # дві різні смуги під одним підписом). Акцент/кольорові ролі
            # лишаються розрахованими схемою.
            if base_hex and base_kind == "нейтраль" and "сім_я" in v:
                hx = base_hex
            вільних += int(bool(вільний))
            ролі.append(dict(слот=ім, роль=v["роль"], зразок=hx,
                             попередження=v.get("попередження")))
        гілки.append(dict(і=i, схема=г["схема"], вага=г["вага"], коли=г["коли"],
                          застереження=г.get("застереження"), ролі=ролі,
                          тон_вільний=вільних, реалізована=True))
    ф = п.get("форма") or {}
    # РОЗРІЗНЮВАЛЬНА ЗДАТНІСТЬ: скільки з гілок реально різні на око. Якщо
    # більшість зразків збігається — фільтр нічого не фільтрує, і це видно тут,
    # а не після того, як людина поскаржиться.
    підписи = ["|".join(r["зразок"] for r in г["ролі"]) for г in гілки if г["реалізована"]]
    # ЗБІГ ТЕПЕР МІРЯЄТЬСЯ, А НЕ РАХУЄТЬСЯ ПО РЯДКАХ. `len(set(підписи))` ловив
    # лише побайтову тотожність, тож дві схеми з ΔE00 = 1.7 між слотами йшли як
    # «дві різні» — при тому, що поріг ПОМІТНОСТІ на шкірі 0.7–1.2, а
    # ПРИЙНЯТНОСТІ 2.1–3.1 (Paravina, 45 спостерігачів, R-PC-09 у colorspace).
    # Тканина не шкіра, тож абсолютні числа звідти не імпортуються — береться
    # порядок величини: пара схем, де КОЖЕН слот ближчий за 2.5 ΔE00, для ока
    # одна схема, і казати «чотири різні» було б неправдою.
    ПОРІГ_ЗБІГУ = 2.5   # T3, порядок величини з R-PC-09; калібрувати на фіді
    _реал = [г for г in гілки if г["реалізована"]]
    _lab = lambda hx: cs.to_lab(tuple(int(hx.lstrip("#")[i:i+2], 16) for i in (0, 2, 4)))
    _той_самий = []
    for a in range(len(_реал)):
        for b in range(a + 1, len(_реал)):
            ра, рб = _реал[a]["ролі"], _реал[b]["ролі"]
            if len(ра) == len(рб) and ра and all(
                    cs.de00(_lab(x["зразок"]), _lab(y["зразок"])) < ПОРІГ_ЗБІГУ
                    for x, y in zip(ра, рб)):
                _той_самий.append((_реал[a]["схема"], _реал[b]["схема"]))
    _групи = list(range(len(_реал)))
    for ім_a, ім_b in _той_самий:
        ia = next(i for i, г in enumerate(_реал) if г["схема"] == ім_a)
        ib = next(i for i, г in enumerate(_реал) if г["схема"] == ім_b)
        стар, нов = max(_групи[ia], _групи[ib]), min(_групи[ia], _групи[ib])
        _групи = [нов if g == стар else g for g in _групи]
    for г, gid in zip(_реал, _групи):
        г["група_збігу"] = gid
    різних = len(set(_групи))
    # ── ЩО ВЗАГАЛІ МОЖНА СТВЕРДЖУВАТИ ПРО ЦЮ ЛЮДИНУ (Н-V03-009, Ш3) ──────────
    # Гейт джерела рахувався від першого дня (`colorspace.gate_conclusions` через
    # `pipeline.підготувати` → `особа.гейт_джерела`) і вмирав усередині пакета:
    # міст його не віддавав, тож ПОКАЗ не мав чим відрізнити «підтон утримано
    # через надійність знімка» від «підтон пораховано, і він вийшов серединним».
    # На екрані обидва стани виглядали однаково порожніми, і жінка читала
    # мовчання як «нам нема чого сказати». Тепер обидва поля їдуть назовні тим
    # самим прийомом, що вже стоїть для `тон_від_рис`.
    # `осі_словами` — БЕЗ ВИГАДУВАННЯ СЛІВ У ПОКАЗІ: слово про тон уже вибране в
    # `palettes.осі` («не стверджується» проти «нейтральна»), і показ мусить
    # брати саме його, а не будувати друге з `джерело_hue`: два слова під одне
    # поняття розійшлися б на першій же правці порога.
    гейт = (п.get("особа") or {}).get("гейт_джерела")
    осі_джерело, осі_словами = None, None
    for г in (п.get("палітри", {}).get("розвилка") or []):
        _ос = ((г.get("спец") or {}).get("палітра_практична") or {}).get("осі") or {}
        if _ос.get("джерело_hue"):
            осі_джерело, осі_словами = _ос["джерело_hue"], _ос.get("словами")
            break
    return _json.dumps(dict(
        гілки=гілки,
        різних_гілок=різних, схем_показано=len(_реал),
        збіглися=[list(p) for p in _той_самий],
        якір=якір, намір=намір,
        контраст=dict(рівень=п["особа"]["рівень"], щілина=п["особа"]["value_gap"]),
        фігура=ф.get("тіло"),
        форма_рахувалась=bool(ф.get("запит_у_фід")),
        формальність=list(п["сценарій"]["діапазон"]),
        вето=п["сценарій"]["вето"],
        основи=п.get("основи_кольорів", {}),
        слід_правил=СЛ.зібрати(),
        правила_без_ід=[dict(ярлик=я, де=д) for я, д in СЛ.без_ід()],
        тон_від_рис=_тон_від_рис_назовні(п),
        гейт=гейт, осі_джерело=осі_джерело, осі_словами=осі_словами,
        вибір_кольору=п.get("вибір_кольору", {})), ensure_ascii=False)


# `тони` (ряд якорів тону на вибір, першим — тон очей) знесено разом із власною
# константою `АХРОМАТИЧНА_МЕЖА` (Н-02-03): ендпойнт без викликача. Поріг K-COL-06
# від цього не зникає — `bases.АХРОМАТИЧНА_МЕЖА` читає його з реєстру
# (`реєстр_правил.C["neutral_C"]`) і працює на живому шляху (`bases.ранг`,
# `bases.за_родом`, `_основи`, `палітри`).


# ── СЛОВА ПРО СВІТЛОТУ ЗНЕСЕНО РАЗОМ З ЇХНІМ ЄДИНИМ ЧИТАЧЕМ ─────────────────
# `_МЕЖІ_L`, `_СЛОВА`, `_слово` («волосся темне») будувала лише `кольори`, і
# жодного іншого викликача в них не було. Ендпойнт знесено (Н-02-03) — шкала
# пішла з ним. Сама перевірка словом не втрачена як задум: `показ.html` має
# власну функцію `щабель()` на тих самих п'яти сходинках, і коли екран перевірки
# кольору буде, будувати їх знову доведеться там, де їх показують.

def _перефарбувати(hex_, L=None):
    """Той самий hex зі світлотою `L` (a*, b* незмінні); без `L` — нормалізований hex."""
    lab = cs.hx(hex_)
    if L is not None:
        lab = (float(L), lab[1], lab[2])
    r, g, b = cs.to_rgb(*lab)
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v * 255))) for v in (r, g, b))


# `кольори` (що код зрозумів із поданих кольорів — словами), `_згода_зчитувань_шкіри`
# (R-PC-09 над двома зчитуваннями обличчя) і `_hex_lab` знесено тут же: усі троє
# були доступні лише через ендпойнт `кольори`. Саме правило R-PC-09 лишається в
# коді й далі — його допуск живе в `colorspace.py:1306` і працює на живому шляху
# (`bridge.py:634` ПОРІГ_ЗБІГУ); знесено не правило, а мертвий екран для нього.

def чипи(вхід=None):
    """Запасний шлях без фото: сходинки, з яких людина обирає себе. Хеси
    рахуються тут, а не вписані рукою, щоб сидіти в тому самому просторі, у
    якому код потім міряє."""
    ш = [_перефарбувати(_hex_lch(L, 26, 52)) for L in (34, 44, 54, 63, 71, 78, 84)]
    в = [_перефарбувати(_hex_lch(L, c, h)) for L, c, h in
         ((12, 4, 60), (24, 14, 55), (36, 20, 58), (48, 24, 62), (60, 26, 70),
          (72, 26, 78), (82, 18, 82), (40, 40, 32))]
    о = ["#3b2c22", "#5d4632", "#7d6a4f", "#6f7f6a", "#5b7f86", "#7c98b5", "#9aa7ad", "#4a5b46"]
    return _json.dumps(dict(шкіра=ш, волосся=в, очі=о), ensure_ascii=False)


def _hex_lch(L, C, h):
    """hex із LCh; хрома обрізається стелею `cs.c_max`, щоб колір був відтворюваний."""
    import math
    c = min(C, cs.c_max(L, h))
    a, b = c * math.cos(math.radians(h)), c * math.sin(math.radians(h))
    r, g, bl = cs.to_rgb(L, a, b)
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v * 255))) for v in (r, g, bl))
