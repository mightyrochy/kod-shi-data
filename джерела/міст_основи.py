# ── ОСНОВИ — РОЗБИТТЯ ПРОСТОРУ, А НЕ СПИСОК РУКАМИ ──────────────────────────
# ЩО БУЛО. Двадцять два рядки з hex, зашитих руками, без джерела й без T-мітки.
# Аудит на повному каталозі показав, що вони випадкові в ОБИДВА боки:
#   · дев'ять пар ближчі за ΔE00 10 (нейві/темно-синій 3.1, коричневий/шоколад
#     5.5, білий/молочний 6.2) — вибір між ними був несправжній: код їх не
#     розрізняє;
#   · 27 слів каталогу, 1 073 речі (чверть кольорового запасу) не мали бази
#     ближче за 10 ΔE00 — блакитний 248, червоний 142, синій 112, зелений 67;
#   · база «рожевий» стояла за 13.8 ΔE00 від каталожного «рожевого», тобто
#     таблиця розходилась із власними назвами.
#
# ЧОМУ НЕ ВИВОДИТИ СПИСОК ІЗ КАТАЛОГУ. Спроба була, і вона хибна за формою:
# словник людини став би функцією від того, що завіз магазин цього сезону.
# Наступного місяця «бірюзовий» зник би з переліку, і жінка не змогла б сказати
# те, що хотіла.
#
# ЩО НАТОМІСТЬ. Основи — РОЗБИТТЯ носибельного простору, яке в проєкті вже є:
#   · хроматика: 7 сімей тону × тепла/холодна дуга × смуги світлоти
#     (`palettes.СІМ_Ї`, версії сімей — T3-практика, тема-2), обрізано стелею
#     реальної поверхні (Pointer, R-COL-12, `cs.c_max_поверхня`);
#   · нейтралі: та сама вісь світлоти при C* нижче ахроматичної межі
#     (K-COL-06) — тон у нейтралі не значить нічого, тому ділиться лише L*.
# Межі [5, 95] і [6, 80] не нові: вони стоять хардкапами у `_вікно_L`/`_вікно_C`.
#
# ЩО З ЦЬОГО ВИПЛИВАЄ САМО:
#   · універсальність — клітинка «тепла синя, світла» існує, навіть коли її нема
#     в наявності; запас стає ВЛАСТИВІСТЮ клітинки, а не умовою її існування;
#   · нема дублів за побудовою — клітинки не перетинаються, а не фільтруються
#     попарно постфактум;
#   · зникає третя таблиця: `_ОСНОВИ`, `verify.ЛЕКСИКОН` і сім'ї більше не
#     розходяться, бо джерело одне.
# Ранг (`bases.ранг`) не змінився: він ранжує ту таблицю, яку йому дають.
СМУГ_L = 5
МЕЖІ_ПРОСТОРУ_L = (5.0, 95.0)
МЕЖІ_ПРОСТОРУ_C = (6.0, 80.0)

# ── СМУГИ ХРОМИ — ВІСЬ ВИБОРУ, А НЕ ФІЛЬТР ─────────────────────────────────
# Стеля хроми за законом площ Манселла не належить ґратці: код тримає
# виміри й ТВЕРДІ ФІЗИЧНІ обмеження, а
# композиційне й культурне судження належить моделі. «Велика річ не може бути
# гучною» — судження, не фізика. Якщо жінка хоче велику неонову річ, скласти з
# неї цілий образ — задача моделі; не показати їй цей колір взагалі — не задача
# нікого. Закон площ лишається в темі-2 як знання для того шару, який судить.
# Єдина стеля, що лишилась, — фізична: скільки хроми дає фарбована поверхня на
# цій світлоті (Pointer, R-COL-12, `cs.c_max_поверхня`).
СМУГИ_ХРОМИ = ("приглушені", "середні", "насичені")
ҐРАТКА_КЕШ = {}



def ґратка_основ():
    """Носибельний простір клітинками. Рахується раз: від людини не залежить."""
    if ҐРАТКА_КЕШ:
        return ҐРАТКА_КЕШ["основи"], ҐРАТКА_КЕШ["порядок"]
    осн, порядок = {}, []
    # ── хроматика: сім'я × дуга × смуга світлоти ──
    Llo, Lhi = МЕЖІ_ПРОСТОРУ_L
    Ls = [Llo + (Lhi - Llo) * (i + 0.5) / СМУГ_L for i in range(СМУГ_L)]
    _L_МІН = _КТ.L_МІН                           # той самий T3, що в `palettes.кольори`: одна межа в `колір_тон`
    for сім, в in _PS.СІМ_Ї.items():
        for дуга in (в["тепла"], в["холодна"]):
            if not дуга:
                continue
            # центр — середина дуги на колі художника, підпис — версія сім'ї, як у фішок палітри (2.14-А: доти знак
            # b* центру CIELAB підписував холодну зелену й холодну жовту «теплими», теплу синю й фіолетову — «холодними»)
            h = _PS.середина_дуги(дуга)
            темп = _PS.версія_дуги(сім, дуга)
            for L in Ls:
                if L < _L_МІН.get(сім, 0.0):
                    continue
                стеля_пов, _ = cs.c_max_поверхня(L, h)
                верх = min(МЕЖІ_ПРОСТОРУ_C[1],
                           стеля_пов if стеля_пов else МЕЖІ_ПРОСТОРУ_C[1],
                           2500.0 / max(L, 1e-6))
                if верх < МЕЖІ_ПРОСТОРУ_C[0]:
                    continue                      # тканина цього кольору не дає — фізика, не смак
                for і_см, см in enumerate(СМУГИ_ХРОМИ):
                    C = МЕЖІ_ПРОСТОРУ_C[0] + (верх - МЕЖІ_ПРОСТОРУ_C[0]) * (і_см + 1) / len(СМУГИ_ХРОМИ)
                    lab = _PS.lab_з_lch(L, C, h)
                    # K-COL-06: клітинка, яку сам код визнає нейтраллю (ахромат
                    # чи нейтральна сім'я — `колір_образу.нейтраль`), не належить
                    # хроматичній гілці — інакше «теплий білий»/«рожевий
                    # приглушений» (C трохи нижча за 12, назва — з лексикону
                    # кольорових сімей) потрапляє під роль «нейтраль»
                    # (`bases.за_родом`, Cstar<12) під власною колірною назвою.
                    # Виміряно пробою `nejtral_chypy.py`: без цього рядка —
                    # 2 з 7 рекомендованих «нейтральних» чипів («рожевий»,
                    # «білий·тепла») насправді з хроматичної гілки.
                    if _КО.нейтраль(lab):
                        continue
                    # K-PAL-11: слово металевого блиску (`_V.МЕТАЛИ`) не підписує
                    # клітинку ҐРАТКИ — клітинка не річ, фактури в неї нема
                    # (вимір РЕЧЕЙ це слово лишає —
                    # `жнива_v2` цю функцію не викликає).
                    ім, _як = _PS.назва(lab, виключити=_V.МЕТАЛИ)
                    ключ = "%s·%s·%d·%s" % (ім, темп, round(L), см)
                    if ключ in осн:
                        continue
                    осн[ключ] = (_PS.hex_з_lab(lab), ім)
                    порядок.append(ключ)
    # ── нейтралі: лише світлота, тон не значить нічого (K-COL-06) ──
    for L in Ls:
        lab = (L, 0.0, 0.0)
        ім, _як = _PS.назва(lab, виключити=_V.МЕТАЛИ)
        # Нейтраль є в КОЖНІЙ смузі хроми: вона не має тону, тож перемикач
        # смуги не повинен її ховати — інакше на «насичених» зникає чорний.
        for см in СМУГИ_ХРОМИ:
            ключ = "%s·нейтраль·%d·%s" % (ім, round(L), см)
            if ключ not in осн:
                осн[ключ] = (_PS.hex_з_lab(lab), ім)
                порядок.append(ключ)
    ҐРАТКА_КЕШ["основи"], ҐРАТКА_КЕШ["порядок"] = осн, порядок
    return осн, порядок


# ── ВІКНО ОСНОВИ: ЧИ МОЖЕ ОБРАНА ОСНОВА СТАТИ ВЕЛИКОЮ РІЧЧЮ ─────────────────
# Основа — клітинка ґратки вище: сім'я тону × смуга світлоти × смуга хроми. «Річ у вікні
# основи» — річ, що могла б бути цією клітинкою: тон у дузі сім'ї основи, світлота в смузі її
# клітинки, хрома не нижча за поріг кольору (та сама межа, що в рядку обраної основи пулу,
# `палітра_запити`). Смугу хроми вікно не бере: гаму судить інше правило, а тут питання —
# чи цей колір такої світлоти буває одягом. ВИМІРЯНО на файлі 1551: основа «м'ятний·86»,
# тональна; у пулі 11 носіїв тону схеми — усі аксесуари, руки 1–2 тримали тон оливковою
# сукнею L* 53 (та сама сім'я, світлота на смугу й більше нижче), а `схема_вийшла` казала «так».
_ПІВСМУГИ_L = (МЕЖІ_ПРОСТОРУ_L[1] - МЕЖІ_ПРОСТОРУ_L[0]) / СМУГ_L / 2.0


def смуга_L_основи(hex_):
    """(L_min, L_max) — смуга світлоти клітинки ґратки навколо основи (±`_ПІВСМУГИ_L`).

    Одна смуга на суд і добір: нею `вікно_основи` міряє «основа на великій», і
    її ж міст кладе в `основа` специфікації — рядок домінанти пулу (`palette.запит_у_фід`)
    шукає одяг саме там, де суд його лічитиме."""
    L = cs.lch(cs.hx(hex_))[0]
    return (round(L - _ПІВСМУГИ_L, 1), round(L + _ПІВСМУГИ_L, 1))


def вікно_основи(hex_):
    """Опора `within` (`колір_річ.опора_вікна`) кольорової основи: дуга сім'ї її тону
    (`palettes.сім_я_тону`; кут поза сім'ями — ±20°), смуга світлоти її клітинки ґратки
    (`смуга_L_основи`) і хрома від порогу кольору (`палітра_гамут.поріг_кольору`)."""
    L, _C, h = cs.lch(cs.hx(hex_))
    сім = _PS.сім_я_тону(h)
    дуга = сім[2] if сім else ((h - 20.0) % 360.0, (h + 20.0) % 360.0)
    return _КР.опора_вікна(L=смуга_L_основи(hex_), C=(_ПГ.поріг_кольору(h, L), 1000.0),
                           дуга=дуга)


def одяг_у_вікні(речі, опора):
    """{"так": n, "невідомо": m} — скільки речей великих слотів (`колір_річ.ВЕЛИКІ_ПОВЕРХНІ`)
    лежить у вікні основи `опора` (`колір_річ.відношення`, клас `within`): «невідомо» — колір зі
    слова, чиє вікно заходить у вікно основи частково. Речі без кольору не лічаться.

    Межі кольору речі (`межі_кольору`) спершу відсіюють світлоту й хрому поза вікном — повне
    відношення на колі художника коштує в сотні разів більше, а одягу в каталозі ~8 тис."""
    Lo, Lв, Cо = _КР.не_вимір(опора)["вікно"][:3]
    вих = {"так": 0, "невідомо": 0}
    for r in речі or ():
        if r.get("слот") not in _ПСХ.ВЕЛИКІ_ПОВЕРХНІ or not _КР.межі_кольору(r):
            continue
        м = _КР.межі_кольору(r)
        if м is None or м[1] < Lo or м[0] > Lв or м[3] < Cо:
            continue
        в = _КР.відношення(r, опора, "within")
        if в in вих:
            вих[в] += 1
    return вих


# ── ВІКНО ПЛАШКИ: ВЕСЬ СПЕКТР, ЯКИЙ ВІДПОВІДАЄ СЛОВУ ────────────────────────
# Слово й точка не одне й те саме: люди й магазини кличуть бежевим ширший
# спектр, ніж L*92–96. Тому плашка несе ВІКНО — межі L*, C* і дугу тону — і 3–5 зразків уздовж
# його ГОЛОВНОЇ осі. Вікно — це ПЕРЕТИН двох вікон, які в коді вже є:
#   · вікно СЛОВА — вікно ВЖИТКУ (`verify.вікно_вжитку(назва)`):
#     спектр, яким крамниці цього каталогу вживають слово, той самий, що судить вимір,
#     спір кольору й кадр іншого кольору. `palettes.назва` підписує плашку за
#     `verify.ЛЕКСИКОН`: ЛЕКСИКОН —
#     про те, як звати точку, ВЖИТОК — про те, що слово під собою має);
#     ТОН — ВИНЯТОК, І ВІН ЗА ЛЕКСИКОНОМ: плашка малює КЛІТИНКУ ҐРАТКИ, а
#     клітинка — річ ПІДПИСУ (`palettes.назва`), і дуга клітинки тут не своя, а СІМ'Ї, спільна
#     з сусідками. Саме тоном підпис і розділяє «м'ятний» від «оливкового», а дуга
#     ВЖИТКУ широка з задуму
#     («м'ятний» 78–244°, бо `ФОРМИ` кладуть «фісташковий» у це слово): нею тон плашки не
#     обрізався б зовсім, і градієнт м'ятної клітинки заходив би в оливкове. Межі L* і C*
#     лишаються з ВЖИТКУ, щоб охопити ширший спектр плашок;
#   · вікно КЛІТИНКИ ґратки — смуга світлоти (`_СМУГ_L` на `_МЕЖІ_ПРОСТОРУ_L`),
#     смуга хроми (`_СМУГИ_ХРОМИ`) і дуга тону сім'ї.
# ОДИН СВІДОК. Ні лексикон, ні `_ґратка_основ` тут не чіпаються: вікно клітинки
# ВИВОДИТЬСЯ з того, що ґратка вже віддала (ключ + hex центру), арифметикою на її
# власних числах, а не другою копією її циклу. Зокрема верхня межа смуги хроми не
# перераховується через стелю поверхні: у ґратці центр смуги і Є її верхнім краєм
# (`C = Cmin + (верх-Cmin)*(і+1)/3`), тож крок смуги — це `(C_центру-Cmin)/(і+1)`.
# Дуга береться `palettes.сім_я_тону` — тією самою функцією, якою показ уже
# отримує поле `сім_я` для групування: інакше плашка була б підписана однією
# сім'єю, а розтягнута по дузі іншої.
# ЗРАЗКИ — В ТКАНИНІ, НЕ НА ДИСПЛЕЇ. Кожен зразок обрізається стелею ФАРБОВАНОЇ
# ПОВЕРХНІ (`cs.c_max_поверхня`, R-COL-12) — тією самою, якою ґратка різала
# власні клітинки. Тому темний край рампи не «вигадує» хроми, якої на цій
# світлоті тканина не дає (`палітра_гамут.здійсненність` про це ж саме, тільки
# вироком по вікну, а не по точці).
# ЦЕ ЛИШЕ ПОКАЗ. Вибір не змінився: дотик до плашки і далі пише `база`,
# `база_hex` ЦЕНТРУ і `база_тип` — градієнт не дає обрати точку всередині вікна.
_КРОК_СМУГИ_L = (МЕЖІ_ПРОСТОРУ_L[1] - МЕЖІ_ПРОСТОРУ_L[0]) / СМУГ_L
_ЗРАЗКІВ_ПЛАШКИ = 5


def _вікно_плашки(ключ, hex_центру, дуга_сім_ї, назва):
    """Вікно плашки (перетин вікна слова й клітинки ґратки) + зразки вздовж
    головної осі. `дуга_сім_ї` — дуга з `palettes.сім_я_тону` або None."""
    import math as _math
    частини = str(ключ).split("·")
    смуга = частини[-1] if частини else ""
    L_ц, C_ц, h_ц = cs.lch(cs.hx(hex_центру))
    # ── вікно КЛІТИНКИ ─────────────────────────────────────────────────────
    L_кл = [L_ц - _КРОК_СМУГИ_L / 2, L_ц + _КРОК_СМУГИ_L / 2]
    if смуга in СМУГИ_ХРОМИ and C_ц > МЕЖІ_ПРОСТОРУ_C[0]:
        крок_C = (C_ц - МЕЖІ_ПРОСТОРУ_C[0]) / (СМУГИ_ХРОМИ.index(смуга) + 1)
        C_кл = [C_ц - крок_C, C_ц]
    else:
        C_кл = [C_ц, C_ц]          # нейтраль: тону нема, смуга хроми її не ділить
    h_кл = [float(дуга_сім_ї[0]), float(дуга_сім_ї[1])] if дуга_сім_ї else None
    # ── перетин із вікном СЛОВА — вікном вжитку (Л-10) ─────────────────────
    в_сл = _V.вікно_вжитку(назва) if назва in _V.ЛЕКСИКОН else None
    if в_сл:                       # тон плашки — дугою ЛЕКСИКОНУ (блок вище), решта — з вжитку
        в_сл = в_сл[:4] + (_V.ЛЕКСИКОН[назва][4],)
    L_в, C_в, h_в = list(L_кл), list(C_кл), (list(h_кл) if h_кл else None)
    поза_словом, ширше = [], []
    if в_сл:
        Llo, Lhi, Clo, Chi, д_сл = в_сл
        if max(L_кл[0], Llo) > min(L_кл[1], Lhi):
            поза_словом.append("L*")   # слово дісталось «найближчим», не вікном
        else:
            L_в = [max(L_кл[0], Llo), min(L_кл[1], Lhi)]
        if max(C_кл[0], Clo) > min(C_кл[1], Chi):
            поза_словом.append("C*")
        else:
            C_в = [max(C_кл[0], Clo), min(C_кл[1], Chi)]
        if Llo < L_кл[0] - 1e-9 or Lhi > L_кл[1] + 1e-9:
            ширше.append("L*")
        if Clo < C_кл[0] - 1e-9 or Chi > C_кл[1] + 1e-9:
            ширше.append("C*")
        if д_сл and h_кл:
            a, b = float(д_сл[0]), float(д_сл[1])
            у_дузі = в_дузі(h_ц, (a, b))
            if not у_дузі:
                поза_словом.append("тон")
            else:
                назад = min(_КТ.хід(h_кл[0], h_ц), _КТ.хід(a, h_ц))
                вперед = min(_КТ.хід(h_ц, h_кл[1]), _КТ.хід(h_ц, b))
                h_в = list(_КТ.розширити_дугу((h_ц, h_ц), назад, вперед))
                if _КТ.хід(a, h_ц) > _КТ.хід(h_кл[0], h_ц) + 1e-9 \
                        or _КТ.хід(h_ц, b) > _КТ.хід(h_ц, h_кл[1]) + 1e-9:
                    ширше.append("тон")
    # ── ГОЛОВНА ВІСЬ: світлота проти тону, в одних одиницях ────────────────
    # L* і градуси не порівнюються навпростець. Дуга переводиться в ДОВЖИНУ дуги
    # в площині a*b* на хромі клітинки (C·Δh у радіанах) — це ті самі одиниці
    # Lab, що й L*, тож «ширше» означає ширше по простору, а не по шкалі.
    ш_L = max(0.0, L_в[1] - L_в[0])
    ш_град = ширина_дуги(h_в) if h_в else 0.0
    ш_тону = C_ц * _math.radians(ш_град)
    якщо_тон = ш_тону > ш_L
    вісь, ширина = ("тон", ш_тону) if якщо_тон else ("світлота", ш_L)
    # ── ЗРАЗКИ ─────────────────────────────────────────────────────────────
    точки = []
    for і in range(_ЗРАЗКІВ_ПЛАШКИ):
        t = і / (_ЗРАЗКІВ_ПЛАШКИ - 1)
        if якщо_тон:
            точки.append((L_ц, C_ц, (h_в[0] + ш_град * t) % 360))
        else:
            точки.append((L_в[1] - ш_L * t, C_ц, h_ц))   # світлий → темний край
    зразки, обрізано = [], 0
    for L, C, h in точки:
        стеля, _дж = cs.c_max_поверхня(L, h)
        C_з = min(C, стеля) if стеля else C
        if C_з < C - 1e-6:
            обрізано += 1
        зразки.append(_PS.hex_з_lab(_PS.lab_з_lch(L, C_з, h)))
    чому = ("тон ширший: %.1f одиниць Lab по дузі (%.0f°) проти %.1f L*"
            % (ш_тону, ш_град, ш_L)) if якщо_тон else \
           ("світлота ширша: %.1f L* проти %.1f одиниць Lab по дузі (%.0f°)"
            % (ш_L, ш_тону, ш_град))
    return dict(слово=назва,
                L=[round(L_в[0], 1), round(L_в[1], 1)],
                C=[round(C_в[0], 1), round(C_в[1], 1)],
                тон=([round(h_в[0], 1), round(h_в[1], 1)] if h_в else None),
                вісь=вісь, ширина=round(ширина, 1), чому=чому,
                зразки=зразки, обрізано_стелею=обрізано,
                слово_ширше=ширше, поза_словом=поза_словом)


def основи(F, source="uncontrolled", самозвіт=None, intent="conventional", макіяж=None, *, прогін_руки=None):
    """Ранг основ під людину. Таблиця _ГРУПИ_ОСНОВ більше не використовується —
    чому саме, розписано в основи.py: вона рахувала одну вісь (підтон, надійність
    0.15), рубала її порогом, якого реальні профілі не переходять, і віддавала
    трьом різним людям один і той самий список. Лишена в файлі як історія."""
    # САМОЗВІТ ЇДЕ В ТЕМПЕРАТУРУ. Картки біля обличчя (золото/срібло, оптичний/вершковий білий, теплі/холодні
    # нейтралі) впливали лише на `bases.ранг`. Тобто єдиний канал, який не залежить від
    # камери — і на який показує сам рядок `деградація` палітри, — до палітри не доходив.
    t = П.температура(F, source=source, самозвіт=самозвіт)
    к = _O.контраст_особи(F, source)
    # ── ҐРАТКА ПІД'ЄДНАНА ─────────────────────────────────────────────────
    # Ранг не змінився — він ранжує ту таблицю, яку йому дають. Змінилось те, ЩО
    # йому дають: замість 22 рядків, зашитих руками, розбиття носибельного
    # простору (7 сімей × тепла/холодна дуга × 5 смуг світлоти × 3 смуги хроми,
    # обрізано стелею фарбованої поверхні). Людина обирає з усього законного;
    # ранг каже, що з цього їй радять, і ряд «інші» ніколи не ховається.
    _осн_таб, _осн_поряд = ґратка_основ()
    ранжовані, пояснення = ОС.ранг(
        F, _осн_таб, _осн_поряд, самозвіт=самозвіт,
        контраст=dict(щілина=(к.get("value_gap") if к.get("доступно") else None),
                      value_gap=(к.get("value_gap") if к.get("доступно") else None),
                      рівень=к.get("рівень"),
                      # слід макіяжу й L шкіри (опора важеля) — з тієї самої особи, що
                      # читають `palette.поверхи` і суд K-CLR-02: один ліміт на три місця
                      макіяж=к.get("макіяж"), L_шкіри=к.get("L_шкіри")),
        надійність=П.reliability(source),
        # ХРОМА ЗІ СЛОВ ЛЮДИНИ: bases.ЦІЛЬ_ХРОМИ знає «приглушені/яскраві» —
        # це картка «нейтралі» показу (`барви_хрома`), а не картка «барви» («бачу різницю»).
        # Доти сюди йшло «не бачу різниці», ціль стояла на 12, і кольорові основи вилітали.
        барви=((самозвіт or {}).get("барви_хрома") or (самозвіт or {}).get("барви")),
        # `_intent`: ранг основ наміру не читає свідомо (див. `bases.ранг`) — намір лишається входом палітри акцентів і композитора.
        _intent=intent, макіяж=макіяж, прогін_руки=прогін_руки)
    # ── СІМ'Я КЛІТИНКИ ЇДЕ НАЗОВНІ ПОЛЕМ ДЛЯ ГРУПУВАННЯ КОЛЬОРІВ ───────────
    # Показ мусить скласти чипи ГРУПАМИ, а сім'ї в рядку рангу не було: ключ
    # клітинки несе назву·температуру·світлоту·смугу, і сім'я з нього
    # ВИВОДИТЬСЯ НЕ ОДНОЗНАЧНО — лексиконна назва («кемел», «теракотовий»)
    # належить сім'ї не за підписом, а за дугою тону. Парсити підпис у JS
    # означало б завести ДРУГУ таблицю сімей поруч із `palettes.СІМ_Ї` — рівно
    # ту розбіжність, проти якої заведена ґратка (див. блок «ОСНОВИ — РОЗБИТТЯ
    # ПРОСТОРУ» вище).
    # Тому сім'я береться з коду й рахується тут, з hex-а клітинки, тією самою
    # функцією, якою її обрала ґратка (`palettes.сім_я_тону`, правило нічиєї —
    # ПОРЯДОК оголошення). Нейтраль тону не має (K-COL-06), тож її сім'я — сама
    # нейтральність, і межа та сама, за якою `за_родом` ділить ряд.
    # ПОЛЕ ОДНЕ. `_ґратка_основ` не чіпається навмисно: її вікна править інша
    # сесія, і розкладка екрана не має права залежати від того, чим скінчиться
    # та правка.
    for _x in ранжовані:
        _C = (_x.get("осі") or {}).get("Cstar")
        if _C is None or _C < ОС.АХРОМАТИЧНА_МЕЖА:
            _x["сім_я"], _с = "нейтраль", None
        else:
            _с = _PS.сім_я_тону(cs.lch(cs.hx(_x["hex"]))[2])
            # `None` тут — чесна відповідь «кут поза всіма дугами `СІМ_Ї`», а не
            # привід вигадати сім'ю: показ покаже таку клітинку окремою групою.
            _x["сім_я"] = (_с[0] if _с else None)
        # ── ВІКНО ПЛАШКИ ЇДЕ ТИМ САМИМ РЯДКОМ ──────────────────────────────
        # Дуга береться з того ж `сім_я_тону`, що й сім'я чипа: одна відповідь на
        # питання «якої сім'ї ця клітинка» — і для групування, і для спектру.
        _x["вікно"] = _вікно_плашки(_x["ключ"], _x["hex"], (_с[2] if _с else None),
                                    _x.get("назва"))
    нейтр, кольор = ОС.за_родом(ранжовані)
    # `поділ` сам відсікає все, що нижче ПІДЛОГИ_РЕКОМЕНДАЦІЇ, тож група може
    # вийти й порожньою — і це чесна відповідь: «для вас тут нема нічого, що
    # код готовий назвати рекомендованим». Порожній ряд краще за перші три
    # з балом 0.3, підписані як рекомендовані.
    # ── ВІДСІЧКА В КОЖНІЙ СМУЗІ ОКРЕМО ─────────────────────────────────────
    # Показ фільтрує ряд за смугою хроми, а приглушені майже завжди набирають
    # більше. Смуга — вибір смаку (кнопка «Гама»), тож найкращі мусять бути
    # названі В КОЖНІЙ смузі.
    # Виміряно до правки: #f0d5c8 → нейтралі {приглушені: 4, середні: 1},
    # кольори {приглушені: 4, середні: 1}, насичені — нічого.
    def _смуга(x):
        """Смуга хроми клітинки — останній сегмент її ключа."""
        return str(x.get("ключ", "")).split("·")[-1]
    def _світлота(x):
        """Смуга світлоти клітинки — передостанній сегмент її ключа."""
        return str(x.get("ключ", "")).split("·")[-2]
    # ── І В КОЖНІЙ СМУЗІ СВІТЛОТИ ТЕЖ ─────────────────────────────────────
    # Відсічка по смугах хроми гарантувала, що «середні» й «насичені» не
    # порожні, — але всередині смуги перші 3–6 за балом майже завжди лежали
    # на ОДНІЙ світлоті, і ряд «рекомендовані» виходив смугою світлоти.
    # ВИМІРЯНО до правки (три профілі `проби/rang_відсічка.py`): std L*
    # рекомендованих 6.4 / 0.1 / 12.5 при розкиді ґратки 23.5; профіль 1 —
    # у смузі L 68 шість кольорів над підлогою і ЖОДНОГО в ряду, профіль 3 —
    # у смугах L 14 і L 32 по 4–7 над підлогою і жодного в ряду. Тобто ряд
    # звужувала не K-CLR-02 (вона діє підлогою: що нижче 0.5, того в ряду нема),
    # а лічба «перші n».
    # ЧОМУ ЦЕ НЕ СУПЕРЕЧИТЬ K-CLR-02. Правило вже відпрацювало в балі (вісь
    # контрасту — перша за вагою, повна ціна за перевищення) і в підлозі:
    # смуга світлоти, де жодна клітинка не дійшла до 0.5, порожня й лишається,
    # і ряд каже про це словами (`ширина_ряду` нижче). Гарантія стосується лише
    # клітинок, які код ВЖЕ не має підстав відкинути, — а серед них найкращу
    # з кожної смуги світлоти видно, як і найкращу з кожної смуги хроми:
    # світлота речі задається самою річчю (пальто темне, блуза світла), і
    # «найкраща темна основа для вас» — окреме питання від «найкраща основа».
    # Скільки — як і доти (за розривом балу); змінюється лише СКЛАД.
    def _відсічка(клітинки):
        """Які клітинки цієї смуги хроми йдуть у «найкращі»: серед тих, що над
        `ОС.ПІДЛОГА_РЕКОМЕНДАЦІЇ`, — по одній найсильнішій на КОЖНУ смугу
        світлоти, далі решта за балом до числа `ОС.поділ`.

        Гарантія на смугу світлоти стоїть ПЕРЕД лічбою й може її перевищити:
        коли смуг більше, ніж `n`, у ряд ідуть усі гаранти, а решти нема.
        Так і задумано — порожня смуга тут означала б «для вас такої основи
        нема», а це неправда, і саме так ряд читався до правки (причина й
        виміри — в коментарі вище). Порожньою смуга лишається тільки тоді,
        коли в ній жодна клітинка не дійшла до підлоги."""
        n = ОС.поділ(клітинки, мінімум=3, максимум=6)
        над = [x for x in клітинки if x["бал"] >= ОС.ПІДЛОГА_РЕКОМЕНДАЦІЇ]
        найкращі = {}
        for x in над:                       # `клітинки` вже за спаданням балу
            найкращі.setdefault(_світлота(x), x)
        гарант = list(найкращі.values())
        решта = [x for x in над if x not in гарант]
        вибір = гарант + решта[:max(0, n - len(гарант))]
        return sorted(вибір, key=lambda x: -x["бал"])
    рек_н, рек_к = [], []
    for смуга in ("приглушені", "середні", "насичені"):
        рек_н += _відсічка([x for x in нейтр if _смуга(x) == смуга])
        рек_к += _відсічка([x for x in кольор if _смуга(x) == смуга])
    рек = рек_н + рек_к
    ключі_рек = {x["ключ"] for x in рек}
    інші = [x for x in ранжовані if x["ключ"] not in ключі_рек]
    нейтр, кольор, м_н, м_к = рек_н, рек_к, len(рек_н), len(рек_к)
    # ── ШИРИНА РЯДУ — СЛОВАМИ ЖІНЦІ, НЕ МОВЧАННЯМ ───────────────────────────
    # Третє місце дії K-CLR-02 (пояснення). Коли ціла смуга світлоти не дійшла
    # до підлоги, ряд називає її і причину з найкращої її клітинки: «темніші
    # перевищують ваш контраст біля обличчя». Показ бере слова звідси, а не
    # вигадує свої.
    _є = sorted({int(_світлота(x)) for x in рек})
    _нема = []
    for _L in sorted({int(_світлота(x)) for x in ранжовані}):
        if _L in _є:
            continue
        _кращ = max((x for x in ранжовані if int(_світлота(x)) == _L),
                    key=lambda x: x["бал"], default=None)
        if _кращ is None:
            continue
        _ліміт = пояснення.get("ліміт_контрасту")
        _чому = ("перевищують ваш контраст біля обличчя"
                 if _кращ["перепад"] > (_ліміт or 0) else
                 "недобирають до вашого контрасту біля обличчя")
        _нема.append(dict(світлота=_L, найкращий_бал=_кращ["бал"], чому=_чому))
    ширина = dict(смуги_світлоти=_є, без_рекомендацій=_нема,
                  ліміт_контрасту=пояснення.get("ліміт_контрасту"),
                  правило="K-CLR-02")
    if _нема:
        _темн = [d for d in _нема if d["світлота"] < min(_є, default=0)]
        _світл = [d for d in _нема if d["світлота"] > max(_є, default=100)]
        _частини = []
        if _темн:
            _частини.append("темніші за L* %d %s" % (min(_є), _темн[-1]["чому"]))
        if _світл:
            _частини.append("світліші за L* %d %s" % (max(_є), _світл[0]["чому"]))
        ширина["словами"] = ("ряд вузький за світлотою: %s (ваш перепад волосся↔шкіра %s L*, K-CLR-02)"
                             % ("; ".join(_частини) or "частина смуг світлоти нижче підлоги",
                                ("%.0f" % _ліміт) if _ліміт is not None else "не виміряний"))
        СЛ.запис("K-CLR-02", "base_row_narrowed_by_lightness", "основи",
                 значення="смуги L* %s без рекомендацій, лишились %s"
                          % ([d["світлота"] for d in _нема], _є),
                 сила=round(len(_нема) / max(1, len(_нема) + len(_є)), 2),
                 напрям="підлога рекомендації (strong при перевищенні)")
    return dict(клас=t.get("клас") if t.get("придатно") else "нейтральна",
                сила_підтону=t.get("сила_підтону"),
                # `рекомендовані` лишається — на нього спирається розмітка, що
                # підписує вибір «поза рекомендацією профілю».
                рекомендовані=рек,
                нейтралі=нейтр[:м_н], кольори=кольор[:м_к], інші=інші,
                ширина_ряду=ширина,
                пояснення=пояснення,
                # метал — слово самої людини з драпіровки, коли воно є (K-PC-01: «вибір самої людини»)
                метал=({"золото": "золото", "срібло": "срібло"}.get((самозвіт or {}).get("метал")) or t.get("метал")),
                приклади=t.get("приклади_нейтралей"))

def ранг_основ_hex(шкіра, волосся, очі, макіяж=None, намір="conventional"):
    """Плаский список hex-ів ряду «рекомендовані» — рівно те, що людина бачить
    першим, без решти payload.

    Заведено для виконуваної перевірки в `status`: без нього перевірка мусила б
    сама лізти по ключах JSON, і аудит контрактів справедливо рахував ці ключі
    полями-сиротами (читає status, не пише ніхто зі сканованих модулів). Тобто
    це не зручність, а спосіб не заводити другий, паралельний спосіб читати той
    самий вихід."""
    F = cs.features(cs.hx(шкіра), cs.hx(волосся), cs.hx(очі))
    F, _ = cs.додати_макіяж(F, макіяж)
    о = основи(F, intent=намір, макіяж=макіяж)
    return [x["hex"].lower() for x in (о.get("рекомендовані") or [])]


# СВІТ БУДУЄТЬСЯ РАЗ НА ВХІД (крок 1.1-Б, К-7). Дорога частина «світу» людини — цей пакет (розвилка палітр,
# `pipeline.підготувати`), а не `_збірка` (2 мс): на записаному прогоні `запити` й `від_моделі` будували його наново на
# кожному виклику — 30 побудов на 7 різних входів, а `_збірка` лишається дешевшою за ключ кешу. Кеш за входом
# (`кеш_входу`) віддає копію готового пакета для того самого входу й стану руки 2; пакет від каталогу не залежить.
@КВ.за_входом(8)
def пакет(F, T, зріст, kw, якір=None, намір="conventional", самозвіт=None, вибір=None,
           драп=None, явні=(), *, прогін_руки=None):
    """Пакет `pipeline.підготувати` для цієї людини: розвилка палітр, сценарій, основи.

    Обрана кольорова основа (`вибір`) стає тоновим якорем замість окремого
    `якір`; самозвіт і драпіровка їдуть у пакет, бо їх читають ранг основ і
    палітра (див. коментарі в тілі).

    `явні` — схеми, названі поіменно (вибір жінки). Їдуть у `підготувати` і далі
    в `palette.розвилка`: гейт наміру вирішує, що код радить сам, але названу
    гілку не скасовує, тож вона є в розвилці пакета — а `гілка` в мості і є
    індекс у ній."""
    вибір = вибір or {}
    # Кольорова основа сама стає тоновим якорем. Окремий «якір тону» лишається
    # для випадку нейтральної основи, де користувач задає лише акцент.
    base_hex = вибір.get("база_hex")
    base_kind = вибір.get("база_тип")
    # Кольорова основа задає hue-якір. Нейтральна основа не має
    # надійного hue, тому не використовуємо її LCH-h як тоновий якір.
    еф_якір = base_hex if base_hex and base_kind == "колір" else якір
    # МАКІЯЖ НЕ ЙДЕ В КОНВЕЄР, АЛЕ ЙДЕ В ОСНОВИ. `підготувати` його не знає й
    # падає на несподіваному аргументі; а K-CLR-03 («помада = +1 крок контрасту
    # для низькоконтрастної особи») без нього не працює. Тому виймаємо тут, а
    # не мовчки губимо.
    _мк = dict(kw); макіяж = _мк.pop("макіяж", None)
    # ПОГОДНІ ПОЛЯ НЕ НАЛЕЖАТЬ ПІДГОТОВЦІ ПАЛІТРИ. Вітер,
    # опади й реагенти, `запити` впав: `підготувати` їх не оголошує, а kw їхав
    # сюди нефільтрованим. Регресійний тест при цьому був ЗЕЛЕНИЙ — він шукав
    # слово «вітер» у шаблоні, тобто міряв наявність поля, а не працездатність
    # шляху. Погода потрібна не тут, а в `review`/`крок_редагування`, куди йде
    # окремою дорогою через сценарій. Тому фільтруємо до того, що функція
    # справді оголосила, — тим самим ідіомом, що вже стоїть у pipeline.
    # ── ВІДБІР ЗА СИГНАТУРОЮ, А НЕ ЗА `co_varnames` ────────────────────────
    # Тут стояло `k in K.підготувати.__code__.co_varnames`, і коментар вище
    # називає це «тим самим ідіомом, що вже стоїть у pipeline». Ідіом узято не
    # той: `co_varnames` — це аргументи ПЛЮС ЛОКАЛЬНІ ЗМІННІ функції, а в
    # `підготувати` їх 21 понад 30 параметрів, серед них `форма`, `сцен`, `кат`,
    # `особа`, `аудит`, `розв`. Тобто фільтр пропустив би ключ сценарію з таким
    # іменем прямо у виклик — і впав би TypeError на живому шляху. Показ уже
    # надсилає `формат`; від `форма` це одна літера.
    # ВИМІР 08.09: на нинішньому сценарії не пролізає нічого (усі 5 прийнятих
    # ключів — справжні параметри), тобто діра латентна, як і була в
    # `pipeline.прогін`, звідки цей рядок і скопійовано.
    # `inspect.signature` не може розійтися з функцією, бо вона і є функція; те,
    # що не пройшло, лягає в пакет полем `не_для_підготувати` — шов має право
    # не передати ключ, але не має права про це змовчати.
    import inspect as _inspect
    _приймає = set(_inspect.signature(K.підготувати).parameters)
    _не_для = sorted(k for k in _мк if k not in _приймає)
    _мк = {k: v for k, v in _мк.items() if k in _приймає}
    # ── ДВА КАНАЛИ ВІДПОВІДІ ЛЮДИНИ ЇДУТЬ У КОНВЕЄР ІМЕНОВАНИМИ (Н-V03-007) ──
    # Доти в `підготувати` їхав лише `**_мк` — поля СЦЕНАРІЮ. `самозвіт` лягав у
    # пакет рядком нижче (для брифа й основ) і до палітри не доходив, а `драп`
    # не доходив узагалі: палітрова гілка отримувала `драп=None` завжди, тож
    # `нейтраль_якір` рахував вікно b* з фото навіть тоді, коли людина відповіла
    # на картки. Іменовані аргументи йдуть ПОВЗ фільтр `_приймає` — він стосується
    # тільки `_мк`, — тому обидва параметри мусять бути оголошені в `підготувати`,
    # інакше тут TypeError (саме тому крок сигнатури нероздільний із цим рядком).
    п = K.підготувати(F, зріст_см=зріст, тіло=T, якір_тон=еф_якір, intent=намір,
                      самозвіт=самозвіт, драп=драп, явні_схеми=tuple(явні or ()),
                      насиченість=вибір.get("насиченість"),
                      **_мк, форма_повна=False, прогін_руки=прогін_руки)
    п["самозвіт"] = самозвіт or {}
    п["вибір_кольору"] = вибір
    п["основи_кольорів"] = основи(F, самозвіт=самозвіт, intent=намір, макіяж=макіяж, прогін_руки=прогін_руки)
    п["година"] = kw.get("година")
    п["сценарій_сирий"] = dict(kw)   # для брифа: опади, ошатність із паспорта (05.09)
    if _не_для:
        п["не_для_підготувати"] = _не_для
    return п


def пакет_гілки(d, F, T, зріст, kw, якір=None, намір="conventional", *, прогін_руки=None):
    """Пакет цієї людини І індекс обраної гілки — ОДНИМ виразом на обидва ендпойнти.

    Повертає `(пакет, гілка, схема, підміна)`, де `гілка` — індекс у розвилці ЦЬОГО
    пакета, `схема` — ім'я, яке назвала жінка (або None), а `підміна` — не-None лише
    тоді, коли назване ім'я донести НЕ вдалось.

    `запити` й `від_моделі` мають брати
    гілку ДВОМА різними виразами. Перший читав ІМ'Я (`_індекс_гілки`) над пакетом,
    зібраним із `явні=(схема,)`; другий стояв тут же в мості окремим рядком
    `min(int(d["гілка"]), len(розвилка) - 1)` над пакетом БЕЗ `явні` — і `d["схема"]`
    не читав узагалі. Під стриманим наміром розвилка суду не має тріади в принципі,
    тож обрана на екрані п'ята плитка ставала `min(4, 3) = 3`.
    ВИМІРЯНО на `каталог_повний` (стенд_вх, намір conventional, схема «тріада»):
    пул збирався ТРІАДОЮ (368 речей, дуги 157–187° / 277–307° / 37–67°), а вердикт
    над тим самим образом міряв ПРИГЛУШЕНУ КОМПЛЕМЕНТАРНУ — інші дуги тону, інші
    акцентні слоти, інша підлога хроми, і два K-PAL-18 про акцентні слоти ЧУЖОЇ
    схеми. Два вирази на одне рішення — це і є дефект, тому вираз тут один.

    МОВЧАЗНА ПІДМІНА ЗАБОРОНЕНА. `явні` доносить у розвилку будь-яку схему, яку
    палітра знає (`palette.розвилка`, всі шість). Лишається рівно один стан, де
    донести нічим: імені нема в корпусі взагалі. Тоді лишається давнє поводження —
    номер із затиском (`_індекс_гілки`), — але воно ПЕРЕСТАЄ бути тихим: `підміна`
    несе, що просили, що дісталось і чому, і викликач віддає це полем далі.
    """
    гілка = None if d.get("гілка") is None else int(d["гілка"])
    схема = (str(d.get("схема") or "").strip() or None)
    п = пакет(F, T, зріст, kw, якір, намір, _самозвіт(d), d.get("вибір_кольору"),
               d.get("драп"), явні=((схема,) if схема else ()), прогін_руки=прогін_руки)
    розв = ((п.get("палітри") or {}).get("розвилка") or [])
    # ПОРОЖНЯ РОЗВИЛКА — ЦЕ «ПАКЕТ НЕ ЗІБРАВСЯ» (`готово=False`: нема шкіри чи
    # волосся), а не «нульова гілка»: `_індекс_гілки` на ній віддав би min(n, -1).
    # Номер −1 мовчки означав би ОСТАННЮ гілку там, де гілок нема зовсім.
    і = _індекс_гілки(розв, гілка, схема) if розв else None
    підміна = None
    if схема and not any((г or {}).get("схема") == схема for г in розв):
        дісталось = (розв[і].get("схема") if (і is not None and 0 <= і < len(розв)) else None)
        підміна = dict(поле="схема", просили=схема, дісталось=дісталось,
                       розвилка=[(г or {}).get("схема") for г in розв],
                       чому=("схеми «%s» нема в розвилці цієї людини навіть на пряме "
                             "прохання (`palette.розвилка`, `явні`) — корпус її не знає. "
                             "Узято %s за номером; це сказано полем, а не затиснуто мовчки"
                             % (схема, ("«%s»" % дісталось) if дісталось else "нічого")))
    return п, і, схема, підміна


# ── палітри ─────────────────────────────────────────────────────────
def тон_від_рис_назовні(п):
    """Дуги тону, виведені з РИС людини, у формі, придатній для шару пояснень.

    ЧОМУ ЦЕ ТУТ ЗʼЯВИЛОСЬ. `gate_reach` рахував R-CHEV-14 як «спрацювало й лягло
    в пакет, але МІСТ НЕ ВІДДАЄ». Виміряно: у виході `палітри` було 5 кодів
    правил, і жодного з тонової осі. Тобто вся вісь — дуги на кожну рису, тиск
    індукції, перегуки, утримання K-PC-05 і виключення K-MUA-01 — рахувалась і
    вмирала на межі. Наслідок не в логах: шар ШІ, який пише жінці пояснення,
    НЕ МАВ ДОСТУПУ до тонової осі взагалі й не міг послатись на неї, навіть якби
    хотів. «Код + ші як одне ціле» на цій осі не існувало.

    Віддається саме те, що потрібно для пояснення й для перевірки, і нічого
    зайвого: яка риса, яка дуга, ДАНА чи ОБРАНА, з якою силою індукції, що
    утримано і чому, які кольори виключені й яким правилом."""
    спец_дж = None
    for г in (п.get("палітри", {}).get("розвилка") or []):
        if (г.get("спец") or {}).get("тон_від_рис"):
            спец_дж = г["спец"]["тон_від_рис"]; break
    if not спец_дж:
        return None
    риси = []
    for імʼя, дані in (спец_дж.get("риси") or {}).items():
        дуги = [dict(від=round(d["дуга"][0], 1), до=round(d["дуга"][1], 1),
                     тиск=d.get("тиск_центр"))
                for d in (дані.get("дуги") or [])]
        риси.append(dict(риса=імʼя, зона=дані.get("зона"),
                         рід=дані.get("рід"), h=дані.get("h"),
                         дуги=дуги, чому_нема=дані.get("чому_нема")))
    return dict(
        придатно=спец_дж.get("придатно"),
        утримано=спец_дж.get("утримано"),
        відношення=спец_дж.get("відношення"),
        h_шкіри=спец_дж.get("h_шкіри"),
        риси=риси,
        перегуки=[dict(риси=list(pp.get("риси") or []),
                       Δтемпература=pp.get("Δтемпература"))
                  for pp in (спец_дж.get("перегуки") or [])],
        напруги=[dict(риси=list(pp.get("риси") or []), суть=pp.get("суть"))
                 for pp in (спец_дж.get("напруги") or [])],
        правила=["R-CHEV-14", "K-PC-05"] + (["K-MUA-01"] if any(
            r.get("рід") == "обрана" for r in риси) else []),
        статус=спец_дж.get("статус"))


# ── ЖОДНА СХЕМА НЕ ЗАМКНЕНА: РІДШУ ПОЯСНЮЮТЬ, А НЕ ХОВАЮТЬ ────────────────
# ЩО БУЛО. `palette.розвилка` додавала statement-гілки (тріада; контраст-мисматч)
# ЛИШЕ під statement/editorial, тож під conventional їх у розвилці не існувало —
# а розвилка і є адресний простір вибору (`гілка` = індекс у ній). Жінка бачила
# чотири плитки й не мала ЧИМ обрати п'яту: «Я не бачу можливості вибрати
# тріаду». Перша правка цього рядка показала решту двох окремою некликабельною
# групою «Не цього разу» з причиною «відкривається, коли…» — тобто назвала замок
# уголос, лишивши його замком.
# ЩО ТЕПЕР. Слово власника 21.09: «Не потрібно так категорично. Все можливе має
# бути доступне людині для вибору, можна просто м'яко написати причину, чому вони
# менш "ходові"». Замка нема ніде: `розвилка` бере схеми, названі поіменно
# (`явні`), незалежно від наміру, і екран палітри питає ВСІ шість — вони стоять
# в одному ряду з рештою й вибираються однаково. Гейт наміру лишився там, де був,
# і вирішує рівно одне: що код радить САМ, без прохання. Ваги гілок, ліміт
# K-COMP-03 і провенанс «тріада_не_щоденна» не чіпані — рідкість тепер живе
# нотою, а не відсутністю, і суд від цього не м'якшає.
#
# Скільки кольорових сімей тримає схема — НЕ слово в тексті, а її власна функція
# тону: так число на екрані не може розійтися зі схемою. Число їде заявою
# `colour_families_at_once`, а словом («дві кольорові сім'ї») його робить мовна модель
# без словника відмінків у коді: відмінок рівня в «X замість Y» не справа коду.
# ── ВАГА ГІЛКИ — СЛОВОМ ЖІНКИ, А НЕ ТОКЕНОМ КОРПУСУ ───────────────────────
# ЩО БУЛО ВИДНО ЖІНЦІ. Чип на екрані палітри підписаний «схема · вага», а вага —
# це `палітра_схеми._ПОРЯДОК_ВАГ`: «ядро», «звичайна», «на_межі» і — англійським
# токеном — «statement». Власниця прочитала «тріада · statement» рівно так, як
# воно й читається: як НАМІР виходу, бо `statement` у цій системі і є один із
# чотирьох намірів (`реєстр_правил.INTENT`, паспорт нагоди). Два різні поняття
# під одним словом на одному екрані; код при цьому рахував conventional.
# ЩО ТЕПЕР. Намір екрана й намір шляху образу — одне джерело (`показ.html`,
# `вхідПалітри`), а вага гілки їде ще й СЛОВОМ, яким вона є для жінки: не назвою
# режиму, а мірою того, наскільки цей хід ходовий. Корпусний токен лишається в
# полі `вага` для журналу й гейтів — міняється те, що видно, а не те, що судять.
_ВАГА_СЛОВОМ = {"ядро": "найходовіша", "звичайна": "звичайна",
                "на_межі": "на межі", "statement": "помітна"}
# Код не чистить машинні слова дорогою до екрана:
# `_МАШИННЕ` (регулярка, що знімала ID правил і хвіст «під intent=…») і `_людською`: код брав
# текст корпусу, писаний для стиліста, і чистив його дорогою до екрана. Обидва прибрано разом
# із фразами — код екранові тексту вже не віддає взагалі, а віддає ЗАЯВИ кодами
# (`_нота_гілки` нижче, `палітра_схеми.ЗАЯВИ_НОТИ`), і речення складає мовна модель. Сире
# поле гілки (`застереження` / `коли`) лишається як було — для моделі, суду й звіту, і як
# видимий запас, коли заяв на пару нема.


def _сімей_тону(схема):
    """Скільки РІЗНИХ кольорових сімей тримає схема — з її власної функції тону
    (`палітра_схеми.СХЕМИ[схема]["тон"]`), а не з підпису. Гілка-концепт, якої в
    `СХЕМИ` нема (контраст-мисматч), чесно віддає None, а не вигадане число."""
    сп = П.СХЕМИ.get(схема)
    if not сп:
        return None
    return len({v for v in сп["тон"](0.0).values() if isinstance(v, tuple)})


def _нота_гілки(г, реалізована=True):
    """Повідомлення про одну гілку КОДАМИ: чому цей хід рідший і/або чого код про нього ще
    не вміє. Тоном поради, не умовою доступу. None — коли казати нема чого.

    ДВІ РІЗНІ РЕЧІ, І ВОНИ НЕ ЗЛИТІ. Рідкість — судження КОРПУСУ («тріада_не_щоденна»,
    «контраст_образу∝контраст_особи»): суть береться з функції тону схеми (скільки
    кольорових сімей — числом у заяві, не словом), з мисматчевого зсуву або з `коли` гілки,
    зачин — із `ТІЛЬКИ_STATEMENT`. Нереалізованість — факт про КОД, і він мусить бути
    сказаний ДО дотику, а не після порожнього пулу.

    Мисматч бере тони в
    базової схеми й міняє драбину світлоти, отже має власні вікна й власний пул.
    Заява про нереалізованість лишається, бо лишається стан, який вона описує (схема,
    якої палітра не знає взагалі), — але вона вже не каже за мисматч. Замість неї мисматч
    несе М'ЯКУ ПРИЧИНУ, чому цей хід рідший: не «не вміємо», а що саме він робить.

    Функція віддає заяви кодами й числами, а речення (разом з відмінком) пише мовна модель. Назва
    схеми в рядок не входить: її малює показ тим самим словом, що стоїть на плитці.
    """
    заяви = []
    # Причина рідкості мисматчу — не число сімей (їх дає БАЗОВА схема, і вони в нього
    # такі самі), а сам хід: контраст образу свідомо не під контраст обличчя.
    _зс = г.get("мисматч") or (г.get("спец") or {}).get("мисматч") or {}
    if _зс:
        суть = [_ВМ.заява("contrast_mismatch")]
        _об = _ВМ.код("contrast_level", _зс.get("рівень_образу"))
        _вл = _ВМ.код("contrast_level", _зс.get("рівень_власний"))
        if _об and _вл:
            суть.append(_ВМ.заява("contrast_mismatch_levels", look_level=_об, own_level=_вл))
    else:
        сімей = _сімей_тону(г["схема"])
        суть = ([_ВМ.заява("colour_families_at_once", families=сімей)] if сімей else [])
    if г.get("поза_порадою"):
        заяви.append(_ВМ.заява("rarer_than_everyday" if г["схема"] in П.ТІЛЬКИ_STATEMENT
                               else "rarer_move"))
        заяви += суть or [_ВМ.заява("stylist_does_not_advise_here")]
    elif _зс:
        # Під сміливим наміром це вже не рідкість — але сказати, ЩО саме вона обирає,
        # усе одно треба: мисматч єдиний із шести міняє не тони, а драбину світлоти.
        заяви += суть
    if not реалізована:
        заяви.append(_ВМ.заява("no_catalogue_filter_yet"))
    return _ВМ.повідомлення("palette_rarer_scheme", *заяви)


def палітри(вхід):
    """Законні схеми — зразками кольору, не числами. Людина закриває розвилку
    сама: код не має чим ранжувати гілки, і вдавати, що має, було б брехнею.

    Чип і стрічка показують перше поєднання прийому з практичної палітри,
    яку читає бриф. Зразки слотів лишаються описом фільтра каталогу."""
    СЛ.почати()
    d = _json.loads(вхід) if isinstance(вхід, str) else вхід
    d = _нормалізувати_вхід(d)
    якір = _якір(d)
    намір = d.get("намір") or "conventional"
    F, T, зріст, kw = _збірка(d, лише_палітра=True)
    вибір_вх = dict(d.get("вибір_кольору") or {})
    # ── БАЗА ЗА ЗАМОВЧУВАННЯМ = ПЕРША РЕКОМЕНДОВАНА ─────────────────────
    # Виміряно: поки база не обрана, всі схеми стоять на одному сталому якорі
    # й сходяться в одне. На тому самому профілі «тональна» й «аналогова»
    # давали 3 однакові слоти з 4 і ΔE00 сер 1.6 — тобто нижче за поріг
    # помітності, дві «різні» схеми були однією. Щойно база задана, ті самі
    # дві схеми розходяться на ΔE00 сер 8.7 (макс 18.5).
    # Тому мовчазний дефолт — не сталий якір, а верх рангу основ. Людина
    # бачить не чотири однакові смуги, а чотири різні, і може переобрати базу.
    if not вибір_вх.get("база_hex"):
        _о = основи(F, самозвіт=d.get("самозвіт"), intent=намір,
                     макіяж=(d.get("сценарій") or {}).get("макіяж"))
        _топ = (_о.get("рекомендовані") or [None])[0]
        if _топ:
            # ТА САМА МЕЖА, ЩО ДІЛИТЬ РЯД. `bases.за_родом`
            # `bases.за_родом` ділить на «нейтралі»/«кольори» по 12 (реєстр
            # `neutral_C`, K-COL-06) і показ підписує чип «нейтраль» по 12. Три
            # місця, дві межі: клітинка з C* 8–12 лежала в ряду «нейтралі», а
            # тут типувалась «колір» і в `_якір_осн` ставала hue-якорем усіх
            # схем. Число читається з реєстру через `bases`, як і в `_основи`.
            вибір_вх.update(база=_топ["ключ"], база_hex=_топ["hex"],
                            база_тип=("нейтраль" if _топ["осі"]["Cstar"] < ОС.АХРОМАТИЧНА_МЕЖА
                                      else "колір"),
                            база_за_замовчуванням=True)
    # ВЕСЬ ПЕРЕЛІК, А НЕ ТОЙ, ЩО ЙОГО РАДИТЬ НАМІР. Екран
    # палітри — місце, де людина обирає, тож він питає схеми поіменно: шість гілок
    # у КОЖНОМУ намірі, з них рідші позначені й пояснені. Гейт наміру від цього не
    # зникає — він і далі вирішує, що код радить сам там, де його не питали
    # (`запити` без вибору жінки: `явні` порожні, розвилка та сама, що й була).
    п = пакет(F, T, зріст, kw, якір, намір, d.get("самозвіт"), вибір_вх, d.get("драп"),
               явні=П.ПОЗА_ЩОДЕННИМ)
    if not п.get("готово"):
        return _json.dumps(dict(помилка=п.get("чому")), ensure_ascii=False)
    гілки = []
    вибір = вибір_вх
    for i, г in enumerate(п["палітри"]["розвилка"]):
        # Гілки-концепти (контраст-мисматч) приходять БЕЗ спец: palette свідомо не
        # фабрикує їм фільтр. Раніше цей рядок падав на них; мовчки викидати теж
        # не можна — тоді «законних схем 4» було б неправдою. Тому вони їдуть із
        # міткою «не реалізовано як фільтр» і вибрати їх не можна.
        спец = (г.get("спец") or {}).get("слоти")
        if not спец:
            гілки.append(dict(і=i, схема=г["схема"], вага=г.get("вага"),
                              вага_словом=_ВАГА_СЛОВОМ.get(г.get("вага"), г.get("вага")),
                              коли=г.get("коли"),
                              застереження=г.get("застереження"),
                              нота_кодами=г.get("нота_кодами"), ролі=[], тон_вільний=0,
                              реалізована=False, рідший=bool(г.get("поза_порадою")),
                              нота=_нота_гілки(г, реалізована=False)))
            continue
        сл = спец
        ролі, вільних = [], 0
        for ім in СЛОТИ:
            v = сл.get(ім)
            if not v or not v.get("L"):
                continue
            # ЗРАЗОК МУСИТЬ ПОКАЗУВАТИ ТЕ, ЩО ПІДЕ В ПРОМПТ. Виміряно:
            # `бриф.колір_слота` домножує хрому на НАСИЧЕНІСТЬ[вибір], а сюди
            # множник не передавався — тож вибір «приглушені / середні /
            # насичені» не міняв зразки НІ НА ОДИН БАЙТ (C* сер 46.0 у всіх
            # трьох). Людина тисне кнопку, бачить ті самі кольори й вирішує,
            # що кнопка мертва; а в промпт тим часом їде інша хрома.
            # Показане й надіслане мусять бути одним.
            v = dict(v, _насиченість=Б.НАСИЧЕНІСТЬ.get(
                вибір.get("насиченість") or "середні", 1.0))
            hx, вільний = Б.колір_слота(v, основа=вибір)
            вільних += int(bool(вільний))
            ролі.append(dict(слот=ім, роль=v["роль"], зразок=hx,
                             попередження=v.get("попередження")))
        # Назви схем і прийомів різняться; кольори читаються без нового добору.
        # Мисматч змінює контраст, а прийом успадковує від базової схеми.
        специфікація = г["спец"]
        схема = (специфікація.get("мисматч") or {}).get("базова", г["схема"])
        прийом = {"нейтрали+акцент": "нейтраль_плюс_акцент",
                  "тональна": "тон_у_тон"}.get(схема, схема)
        поєднання = next((п for п in специфікація["палітра_практична"]["поєднання"]
                          if п["прийом"] == прийом), {})
        запасний_прийом = None
        if not поєднання:
            # Відсутній прийом не підміняється іншою трійкою під його назвою.
            # Зразок доступного прийому з того самого джерела має явний підпис.
            поєднання = next(iter(специфікація["палітра_практична"]["поєднання"]), {})
            запасний_прийом = поєднання.get("прийом")
        зразки = [к["hex"] for к in поєднання.get("кольори", [])]
        гілки.append(dict(і=i, схема=г["схема"], вага=г["вага"],
                          вага_словом=_ВАГА_СЛОВОМ.get(г["вага"], г["вага"]),
                          коли=г["коли"], зразки=[з for з in зразки if з],
                          запасний_прийом=запасний_прийом,
                          застереження=г.get("застереження"),
                          нота_кодами=г.get("нота_кодами"), ролі=ролі,
                          тон_вільний=вільних, реалізована=True,
                          рідший=bool(г.get("поза_порадою")), нота=_нота_гілки(г)))
    ф = п.get("форма") or {}
    # РОЗРІЗНЮВАЛЬНА ЗДАТНІСТЬ: скільки з гілок реально різні на око. Якщо
    # більшість зразків збігається — фільтр нічого не фільтрує, і це видно тут,
    # а не після того, як людина поскаржиться.
    підписи = ["|".join(r["зразок"] for r in г["ролі"]) for г in гілки if г["реалізована"]]
    # ЗБІГ ТЕПЕР МІРЯЄТЬСЯ, А НЕ РАХУЄТЬСЯ ПО РЯДКАХ. `len(set(підписи))` ловив
    # лише побайтову тотожність, тож дві схеми з ΔE00 = 1.7 між слотами йшли як
    # «дві різні» — при тому, що поріг ПОМІТНОСТІ на шкірі 0.7–1.2, а
    # ПРИЙНЯТНОСТІ 2.1–3.1 (Paravina, 45 спостерігачів, R-PC-09 у colorspace).
    # Тканина не шкіра, тож абсолютні числа звідти не імпортуються — береться
    # порядок величини: пара схем, де КОЖЕН слот ближчий за 2.5 ΔE00, для ока
    # одна схема, і казати «чотири різні» було б неправдою.
    ПОРІГ_ЗБІГУ = 2.5   # T3, порядок величини з R-PC-09; калібрувати на фіді
    _реал = [г for г in гілки if г["реалізована"]]
    _lab = lambda hx: cs.to_lab(tuple(int(hx.lstrip("#")[i:i+2], 16) for i in (0, 2, 4)))
    _той_самий = []
    for a in range(len(_реал)):
        for b in range(a + 1, len(_реал)):
            ра, рб = _реал[a]["ролі"], _реал[b]["ролі"]
            if len(ра) == len(рб) and ра and all(
                    cs.de00(_lab(x["зразок"]), _lab(y["зразок"])) < ПОРІГ_ЗБІГУ
                    for x, y in zip(ра, рб)):
                _той_самий.append((_реал[a]["схема"], _реал[b]["схема"]))
    _групи = list(range(len(_реал)))
    for ім_a, ім_b in _той_самий:
        ia = next(i for i, г in enumerate(_реал) if г["схема"] == ім_a)
        ib = next(i for i, г in enumerate(_реал) if г["схема"] == ім_b)
        стар, нов = max(_групи[ia], _групи[ib]), min(_групи[ia], _групи[ib])
        _групи = [нов if g == стар else g for g in _групи]
    for г, gid in zip(_реал, _групи):
        г["група_збігу"] = gid
    різних = len(set(_групи))
    # ── ЩО ВЗАГАЛІ МОЖНА СТВЕРДЖУВАТИ ПРО ЦЮ ЛЮДИНУ (Н-V03-009, Ш3) ──────────
    # Гейт джерела рахувався від першого дня (`colorspace.gate_conclusions` через
    # `pipeline.підготувати` → `особа.гейт_джерела`) і вмирав усередині пакета:
    # міст його не віддавав, тож ПОКАЗ не мав чим відрізнити «підтон утримано
    # через надійність знімка» від «підтон пораховано, і він вийшов серединним».
    # На екрані обидва стани виглядали однаково порожніми, і жінка читала
    # мовчання як «нам нема чого сказати». Тепер обидва поля їдуть назовні тим
    # самим прийомом, що вже стоїть для `тон_від_рис`.
    # `осі_коди` — БЕЗ ВИГАДУВАННЯ СЛІВ У ПОКАЗІ: бік осі тону вже вирішено в
    # `palettes.осі` (`withheld` проти `neutral`), і показ мусить брати саме його, а не
    # будувати другий висновок із `джерело_hue`: два означення під одне поняття
    # розійшлися б на першій же правці порога.
    # `осі_коди` несе код замість українського слова («тепла», «не стверджується»).
    # Слово на екрані стоїть сталим написом показу, по одному на код.
    гейт = (п.get("особа") or {}).get("гейт_джерела")
    осі_джерело, осі_коди = None, None
    for г in (п.get("палітри", {}).get("розвилка") or []):
        _ос = ((г.get("спец") or {}).get("палітра_практична") or {}).get("осі") or {}
        if _ос.get("джерело_hue"):
            осі_джерело, осі_коди = _ос["джерело_hue"], _ос.get("коди")
            break
    return _json.dumps(dict(
        гілки=гілки,
        # Скільки з шести код радить САМ під цим наміром: підпис під плитками
        # каже це число, і воно рахується тут, а не складається в JS із двох
        # переліків. Решта — рідші ходи, і вони теж вибираються.
        радить_код=sum(1 for г in гілки if not г["рідший"]),
        різних_гілок=різних, схем_показано=len(_реал),
        збіглися=[list(p) for p in _той_самий],
        якір=якір, намір=намір,
        контраст=dict(рівень=п["особа"]["рівень"], щілина=п["особа"]["value_gap"]),
        фігура=ф.get("тіло"),
        форма_рахувалась=bool(ф.get("запит_у_фід")),
        формальність=list(п["сценарій"]["діапазон"]),
        вето=п["сценарій"]["вето"],
        основи=п.get("основи_кольорів", {}),
        слід_правил=СЛ.зібрати(),
        правила_без_ід=[dict(ярлик=я, де=д) for я, д in СЛ.без_ід()],
        тон_від_рис=тон_від_рис_назовні(п),
        гейт=гейт, осі_джерело=осі_джерело, осі_коди=осі_коди,
        вибір_кольору=п.get("вибір_кольору", {})), ensure_ascii=False)


# `тони` (ряд якорів тону на вибір, першим — тон очей) знесено разом із власною
# константою `АХРОМАТИЧНА_МЕЖА` (Н-02-03): ендпойнт без викликача. Поріг K-COL-06
# від цього не зникає — `bases.АХРОМАТИЧНА_МЕЖА` читає його з реєстру
# (`реєстр_правил.C["neutral_C"]`) і працює на живому шляху (`bases.ранг`,
# `bases.за_родом`, `_основи`, `палітри`).


# ── СЛОВА ПРО СВІТЛОТУ ЗНЕСЕНО РАЗОМ З ЇХНІМ ЄДИНИМ ЧИТАЧЕМ ─────────────────
# `_МЕЖІ_L`, `_СЛОВА`, `_слово` («волосся темне») будувала лише `кольори`, і
# жодного іншого викликача в них не було. Ендпойнт знесено (Н-02-03) — шкала
# пішла з ним. Сама перевірка словом не втрачена як задум: `показ.html` має
# власну функцію `щабель()` на тих самих п'яти сходинках, і коли екран перевірки
# кольору буде, будувати їх знову доведеться там, де їх показують.

def перефарбувати(hex_, L=None):
    """Той самий hex зі світлотою `L` (a*, b* незмінні); без `L` — нормалізований hex."""
    lab = cs.hx(hex_)
    if L is not None:
        lab = (float(L), lab[1], lab[2])
    r, g, b = cs.to_rgb(*lab)
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v * 255))) for v in (r, g, b))


# `кольори` (що код зрозумів із поданих кольорів — словами), `_згода_зчитувань_шкіри`
# (R-PC-09 над двома зчитуваннями обличчя) і `_hex_lab` знесено тут же: усі троє
# були доступні лише через ендпойнт `кольори`. Саме правило R-PC-09 лишається в
# коді й далі — його допуск живе в `colorspace.py:1306` і працює на живому шляху
# (`bridge.py:634` ПОРІГ_ЗБІГУ); знесено не правило, а мертвий екран для нього.

def чипи(_вхід=None):
    """Запасний шлях без фото: сходинки, з яких людина обирає себе. Хеси
    рахуються тут, а не вписані рукою, щоб сидіти в тому самому просторі, у
    якому код потім міряє.

    `_вхід` НЕ ЧИТАЄТЬСЯ СВІДОМО: сигнатура одна на всі ендпойнти диспетчера
    `bridge.виклик` (`функція(вхід)`), а сходинки не залежать від жінки — вона
    саме з них себе й обирає, коли фото ще нема."""
    ш = [перефарбувати(hex_lch(L, 26, 52)) for L in (34, 44, 54, 63, 71, 78, 84)]
    в = [перефарбувати(hex_lch(L, c, h)) for L, c, h in
         ((12, 4, 60), (24, 14, 55), (36, 20, 58), (48, 24, 62), (60, 26, 70),
          (72, 26, 78), (82, 18, 82), (40, 40, 32))]
    о = ["#3b2c22", "#5d4632", "#7d6a4f", "#6f7f6a", "#5b7f86", "#7c98b5", "#9aa7ad", "#4a5b46"]
    return _json.dumps(dict(шкіра=ш, волосся=в, очі=о), ensure_ascii=False)


# ── СХОДИНКА ПОМАДИ Й ПОДІЛ ЗА R-MUA-03 ───────────────────────────────────
# Сходинка рахується `помада.сходинки` тим самим `_hex_lch`, яким
# рахуються чипи шкіри/волосся/очей, а поділ — `помада.поділ` за R-MUA-03. Тут
# лишається сама межа: зібрати людину з входу показу й віддати JSON. Правило —
# у `помада.py`, разом з усім, що воно читає й чого не вміє.
def помади(вхід):
    """Відтінки помади зі сходинки і поділ «рекомендовані тобі / решта» (R-MUA-03).

    Сигнатура та сама, що в решти ендпойнтів диспетчера (`функція(вхід)`). На
    відміну від `чипи`, вхід ЧИТАЄТЬСЯ: сама сходинка від жінки не залежить, а
    поділ залежить цілком — він і є відповідь на «що з цього твоє».

    Без кольорів у вході поділу нема: повертається вся сходинка одним рядом, а
    «поки не знаю твоїх кольорів — покажу всі» каже сам екран сталим написом
    (чесне «без входу», аудит/ПРОДУКТ.md п.4), а не мовчазний порожній ряд. `свій` — hex, названий рукою; він проходить той самий суд і
    НЕ блокується, хай яким буде вердикт."""
    d = _json.loads(вхід) if isinstance(вхід, str) else (вхід or {})
    d = _нормалізувати_вхід(d)
    ряд = ПМ.сходинки(hex_lch)
    видимі = [dict(ключ=x["ключ"], підпис=x["підпис"], сім_я=x["сім_я"], hex=x["hex"])
              for x in ряд]
    сім_ї = []
    for x in видимі:
        if x["сім_я"] not in сім_ї:
            сім_ї.append(x["сім_я"])
    if not (d.get("шкіра") and d.get("волосся") and d.get("очі")):
        # «Поки не знаю твоїх кольорів» — сталий напис екрана (`показ.html`),
        # а не відповідь даних чи `помада.поділ`.
        return _json.dumps(dict(сходинки=видимі, сім_ї=сім_ї, поділ=dict(
            є=False, рекомендовані=[], решта=[x["ключ"] for x in видимі], причини={},
            чому=None), свій=None),
            ensure_ascii=False)
    F, _ш, _вл, _о, _точки = _features(d)
    контраст = _O.контраст_особи(F)
    самозвіт = d.get("самозвіт")
    поділ = ПМ.поділ(ряд, F, контраст, самозвіт=самозвіт)
    свій = ПМ.свій(d.get("свій"), F, контраст, самозвіт=самозвіт)
    return _json.dumps(dict(сходинки=видимі, сім_ї=сім_ї, поділ=поділ, свій=свій),
                       ensure_ascii=False)


def hex_lch(L, C, h):
    """hex із LCh; хрома обрізається стелею `cs.c_max`, щоб колір був відтворюваний."""
    import math
    c = min(C, cs.c_max(L, h))
    a, b = c * math.cos(math.radians(h)), c * math.sin(math.radians(h))
    r, g, bl = cs.to_rgb(L, a, b)
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v * 255))) for v in (r, g, bl))
