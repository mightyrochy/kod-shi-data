# -*- coding: utf-8 -*-
"""ВИМІР, а не твердження: чи справді інтервальна модель формальності знімає
спрацювання K-KOH-02 на high-low і чи не додає нових хибних.

Тема-5 частина VIII заявила числа (точкова 74.1% відхилень, інтервальна 44.2%,
знято 40.4%, нових хибних 0). Заява в тексті — не результат. Тут вона проганяється
на КОДІ, який поїде в продакшн, і числа друкуються разом із діагностикою: які саме
трійки перестали таврувати. Якщо знімається не high-low, а щось інше — це видно.

Прогін: `python3 аудит_формальності.py`. Простір — усі верх×низ×взуття з таблиць типів.
ЧОГО ЦЕЙ ПРОГІН НЕ ДОВОДИТЬ: рівномірна вибірка типів — не реальний каталог.
Обидва числа — ВЕРХНЯ межа суворості, доки не прогнано на живому фіді.
"""
import itertools, statistics
import outfit as O

ВЕРХ = ["вечірня_сукня", "коктейльна_сукня", "футляр", "блейзер", "сорочка", "блуза",
        "кніт", "трикотаж", "футболка", "худі"]
НИЗ = ["джинси", "легінси", "спортивний", "домашнє"]
ВЗУТТЯ = ["човники", "туфлі", "лофери", "черевики", "чоботи", "босоніжки",
          "кросівки", "кеди", "сандалі"]
СЛОТ = {**{t: "верх" for t in ВЕРХ}, **{t: "низ" for t in НИЗ},
        **{t: "взуття" for t in ВЗУТТЯ}}


def _речі(трійка):
    return [dict(річ=t, слот=СЛОТ[t], тип=t, площа=1.0,
                 формальність=O.ТИП_ФОРМАЛЬНІСТЬ.get(t)) for t in трійка]


def точкова(трійка):
    """Стара модель: розкид ТОЧКОВИХ значень > межі.

    ВИПРАВЛЕНО: файл кликав `O.ФОРМ_ДОПУСК`, якої в outfit.py немає — константа
    зветься `ФОРМ_РОЗКИД_МАКС`. Стенд падав AttributeError, тобто головне число
    інтервальної моделі ніхто не міряв. Це той самий клас дефекту, що й у
    наскрізний_гейт: стенд написаний під API, який не долетів."""
    v = [O.ТИП_ФОРМАЛЬНІСТЬ[t] for t in трійка]
    return (max(v) - min(v)) > O.ФОРМ_РОЗКИД_МАКС


def інтервальна(трійка):
    """Нова модель — через РЕАЛЬНУ функцію, не через копію логіки."""
    зн = O.формальність_образу(_речі(трійка))
    return any(z["правило"] == "K-KOH-02" for z in зн)


def прогін():
    трійки = list(itertools.product(ВЕРХ, НИЗ, ВЗУТТЯ))
    т = [k for k in трійки if точкова(k)]
    і = [k for k in трійки if інтервальна(k)]
    знято = [k for k in т if k not in set(і)]
    додано = [k for k in і if k not in set(т)]
    n = len(трійки)
    print("=" * 78)
    print("ФОРМАЛЬНІСТЬ: точкова модель проти інтервальної (гіперребро над образом)")
    print("=" * 78)
    print(f"простір: {len(ВЕРХ)} верх × {len(НИЗ)} низ × {len(ВЗУТТЯ)} взуття = {n} трійок\n")
    print(f"  точкова модель   таврує {len(т):4d} / {n}  ({100*len(т)/n:.1f}%)")
    print(f"  інтервальна      таврує {len(і):4d} / {n}  ({100*len(і)/n:.1f}%)")
    print(f"  знято спрацювань {len(знято):4d}          ({100*len(знято)/max(1,len(т)):.1f}% від точкової)")
    print(f"  НОВИХ спрацювань {len(додано):4d}          <- має бути 0, інакше модель суворіша, "
          f"а не точніша")
    print("\nЩО САМЕ ЗНЯТО (перші 12) — має бути high-low, а не сміття:")
    for k in знято[:12]:
        і_ = [O.ТИП_ІНТЕРВАЛ.get(t) for t in k]
        print("   %-16s %-12s %-12s   %s" % (k[0], k[1], k[2],
              " ".join("%d–%d" % x if x else "—" for x in і_)))
    if додано:
        print("\n⚠ НОВІ спрацювання (регресія):")
        for k in додано[:12]: print("   ", k)
    # роздільна здатність: фільтр, що пропускає майже все, — не фільтр
    print(f"\nРОЗДІЛЬНА ЗДАТНІСТЬ: інтервальна модель пропускає {100*(n-len(і))/n:.1f}% простору. "
          f"\n  Це ВЕРХНЯ межа суворості: типи взяті рівномірно, реальний каталог — ні.")
    return dict(n=n, точкова=len(т), інтервальна=len(і), знято=len(знято), додано=len(додано))


def вечір():
    """Друге вимірювання: чи мовчить вечірній підйом там, де тема-5 показала провал."""
    кейси = [("парк", 19), ("спорт", 18), ("дім", 20), ("транспорт_довгий", 21),
             ("кафе", 19), ("ресторан_високий", 19), ("весілля_вечірнє", 19),
             ("офіс_корпоративний", 19), ("театр", 19)]
    print("\n" + "=" * 78)
    print("ВЕЧІРНІЙ ПІДЙОМ: градуйований за тіром замість плаского +1")
    print("=" * 78)
    for місце, год in кейси:
        база = O.МІСЦЯ_ДІАПАЗОНИ.get(місце, (3, 6))
        с = O.сценарій(місце=місце, година=год)
        плаский = (база[0] + 1, база[1] + 1)
        мітка = "МОВЧИТЬ" if tuple(с["діапазон"]) == tuple(float(x) for x in база) else "підйом "
        print("  %-20s %2d:00  база %d–%d → нове %.1f–%.1f   (плаский +1 дав би %d–%d)  %s"
              % (місце, год, база[0], база[1], с["діапазон"][0], с["діапазон"][1],
                 плаский[0], плаский[1], мітка))


if __name__ == "__main__":
    прогін()
    вечір()
