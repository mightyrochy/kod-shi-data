def довідник():
    """Нагоди, місця й дрес-коди — РІВНО ті ключі, з яких рахує `формальність.сценарій`,
    з межами звідти ж і словами для людини з `ДОВІДНИК_ПІДПИСИ`.

    Порядок — за серединою діапазону (від дому до white tie), щоб плитки й
    списки йшли шкалою ошатності, а не абеткою. `дефолт_діапазон` — той самий
    «широкий дефолт» невідомого середовища, що стоїть в `формальність.сценарій`."""
    import outfit as _O
    import колір_образу as _КОЛІР, реєстр_правил as _РЕЄСТР, формальність as _ФОРМ   # Н-02-01, сесія 4

    def _ряд(група, ключ, діап, **решта):
        """Один рядок довідника: ключ, слова для людини й межі ошатності.

        `плитка` = «цей ключ названо в `ДОВІДНИК_ПІДПИСИ`»: плиткою на екрані
        стає лише те, для чого є ЦІ слова. Решта не зникає й не лишається голим
        ключем: слова їй дає `ПІДПИСИ_НЕ_ПЛИТКИ`, а ключ із підкресленнями —
        останній запас на випадок ключа, якого ще ніхто не назвав."""
        плитка = ключ in ДОВІДНИК_ПІДПИСИ[група]
        підпис, нота = (ДОВІДНИК_ПІДПИСИ[група].get(ключ)
                        or ПІДПИСИ_НЕ_ПЛИТКИ.get(група, {}).get(ключ)
                        or (ключ.replace("_", " "), ""))
        ряд = dict(ключ=ключ, підпис=підпис, нота=нота, діапазон=list(діап),
                   плитка=плитка, **решта)
        if група == "нагоди":
            ряд["сімʼя"] = СІМʼЯ_НАГОДИ.get(ключ, "")
        return ряд
    _шкалою = lambda р: (sum(р["діапазон"]) / 2.0, р["діапазон"][0], р["ключ"])
    таблиці = dict(
        нагоди=sorted((_ряд("нагоди", к, _ФОРМ.МІСЦЯ_ДІАПАЗОНИ[м], місце=м)
                       for к, м in _ФОРМ.НАГОДА_У_МІСЦЕ.items() if м in _ФОРМ.МІСЦЯ_ДІАПАЗОНИ),
                      key=_шкалою),
        місця=sorted((_ряд("місця", к, v) for к, v in _ФОРМ.МІСЦЯ_ДІАПАЗОНИ.items()), key=_шкалою),
        коди=sorted((_ряд("коди", к, v) for к, v in _ФОРМ.КОДИ_ДІАПАЗОНИ.items()), key=_шкалою))
    for група, рядки in таблиці.items():
        ключі = {р["ключ"] for р in рядки}
        зайві = sorted((set(ДОВІДНИК_ПІДПИСИ[група]) | set(ПІДПИСИ_НЕ_ПЛИТКИ.get(група, {}))) - ключі)
        if зайві:
            raise ValueError("довідник: підпис без ключа в коді — %s %s" % (група, зайві))
        обидва = sorted(set(ДОВІДНИК_ПІДПИСИ[група]) & set(ПІДПИСИ_НЕ_ПЛИТКИ.get(група, {})))
        if обидва:
            raise ValueError("довідник: ключ названо двічі, плиткою й не-плиткою — %s %s" % (група, обидва))
    # Сімʼя мусить бути в КОЖНОЇ нагоди й лише зі звісних: список на екрані групує за нею,
    # і ключ без сімʼї тихо випав би з нього — та сама мовчазна втрата, що ловить `зайві`.
    сімʼї = {к for к, _ in СІМʼЇ_НАГОД_ПІДПИСИ}
    безсімейні = sorted(р["ключ"] for р in таблиці["нагоди"] if р["сімʼя"] not in сімʼї)
    if безсімейні:
        raise ValueError("довідник: нагода без сімʼї — %s" % безсімейні)
