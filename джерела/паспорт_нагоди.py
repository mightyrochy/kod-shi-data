        # ВИМІРИ — ОСТАННІМИ, В ОБОХ ГІЛКАХ (НГ-1): вище ще ставиться нагода (типова нагода
        # речі з фото), а виміри виводяться з неї. Код за ними нічого не рахує — НГ-2.
        п["виміри"], п["звідки"] = виміри_нагоди(п, сц)
