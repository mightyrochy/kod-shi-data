    підписи = [р["підпис"] for р in таблиці["нагоди"]]
    повтори = sorted({п for п in підписи if підписи.count(п) > 1})
    if повтори:
        raise ValueError("довідник: два однакові підписи нагод — %s" % повтори)
    # ДОВІДНИК ВИДІВ СТЕРЕЖЕТЬСЯ ТУТ-ТАКИ (НГ-1): нагода без виду, вид без пресету й пресет
    # поза переліком кодів валять збірку так само, як підпис без ключа вище, — бо вимір, який
    # мовчки випав, гірший за відсутній (НГ-2 читатиме саме виміри).
    _звірити_довідник_видів()
    return dict(таблиці, дефолт_діапазон=[3, 6], шкала="1 домашнє … 10 white tie",
                сімʼї_нагод=[dict(ключ=к, підпис=п) for к, п in СІМʼЇ_НАГОД_ПІДПИСИ])


