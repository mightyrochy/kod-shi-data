def мета_на_осі(п, зони=True):
    """Паспорт чи сценарій з однією віссю `мета` → дві осі без втрат.

    «вище» (четверта мета, «10 а») → увага «лестити» + `мета_важливо` [«вище»]: колір і форма не
    читають «вище» як «лестити» (`внутрішня_мова.МЕТИ_З_НАПРЯМОМ`), а K-COL-01 і K-FIT-04 — як довшу лінію;
    ті самі правила читають вісь `мета_важливо`. Однозначно, тож діє завжди.
    «приховати» з відомою зоною → увага «невідомо», зони лишаються: інакше така мета судила б лише зону, а
    палітра, посадка й доза брали б дефолт (`регістр_уваги.мета_образу`). Нова пара «приховати» +
    зони означає «тихо всім образом і ще зона», тож переводиться лише запис без ключа `мета_важливо` (його
    несе кожен чинний паспорт) і лише коли `зони` (сценарій показу шле ключ, лише коли щось обрано).
    Повертає копію; не словник — як є."""
    if not isinstance(п, dict):
        return п
    новий = "мета_важливо" in п
    п = dict(п)
    if "джерело_полів" in п:
        п["джерело_полів"] = {к: _СТ.автор(v) for к, v in (п["джерело_полів"] or {}).items()}
    важл = [к for к in (п.get("мета_важливо") or ()) if к in _PR.МЕТА_ВАЖЛИВО]
    if п.get("мета") == "вище":
        п["мета"], важл = "лестити", list(dict.fromkeys(важл + ["вище"]))
    elif (зони and not новий and п.get("мета") == "приховати"
          and set(п.get("мета_зони") or ()) & set(_ВМ_СХ.ТАБЛИЦЯ["goal_zone"].values())):
        п["мета"] = "невідомо"
    if новий or важл or п.get("мета") is not None:
        п["мета_важливо"] = важл
    return п


def з_показу(с, паспорт=None):
    """(нагода, незнайомі) — з того, що прийшло від показу, і з паспорта випадку.

    Паспорт ПЕРЕВАЖАЄ вибраний сценарій: він зібраний зі слів людини про цю
    конкретну подію, а сценарій — з випадаючого списку. Це та сама асиметрія,
    що вже стоїть у `composer` для ошатності («слова людини — перші»).

    Незнайомі ключі не відкидаються мовчки: вони повертаються другим значенням.
    Викликач вирішує, показати їх чи знехтувати, — але не може НЕ ЗНАТИ про них.
    """
    # Старий запис (одна вісь `мета`) — на дві осі; сценарій показу — лише «вище»
    с = мета_на_осі(dict(с or {}), зони=False)
    п = мета_на_осі(dict(паспорт or {}))
    for запис in (с, п):
        for поле in запис:
            запис[поле] = чинний_ключ(поле, запис[поле])
    нагода, незнайомі = {}, []
    for k, v in с.items():
        if v in (None, ""):
            continue
        if k in _ПОГОДА.ПОЛЯ or k in _ПОГОДА.СЛУЖБОВІ:
            нагода[k] = v
        else:
            незнайомі.append(k)
    for k in _ПОГОДА.ПОЛЯ:
        v = п.get(k)
        if v not in (None, "", []) and v != "невідомо":
            нагода[k] = v
    # ── БЛИЗЬКІСТЬ ДО ПОМЕРЛОГО — КОДОМ ВИМІРУ ПАСПОРТА (п.12) ──────────────
    # Вимір `mourning` (`mourning_closeness`) її слів — не типове коду — їде в `траур.близькість`,
    # звідки термін бере `траурний_регістр.траур_випадку` (`траурний_регістр.ТРАУР_ПЕРІОД`). Регістру
    # він сам не вмикає: лише там, де траур уже названо (поле `траур` чи траурна подія).
    _бл = (п.get("виміри") or {}).get("mourning")
    _т0 = нагода.get("траур") if isinstance(нагода.get("траур"), dict) else {}
    if (_бл in _ТР.ТРАУР_ПЕРІОД and (п.get("звідки") or {}).get("mourning") not in (None, "default", "unknown")
            and (_т0 or потреба_події(нагода)["траур"])):
        нагода["траур"] = dict(_т0, близькість=_бл)
    # ── ЗАМОВЧУВАННЯ ФОРМИ — «НЕВІДОМО» І ДЛЯ ПРАВИЛ (ТИПОВЕ-1) ──────
    # ЩО БУЛО. 11:00, +18 °C і типове місце плитки, яких вона не називала (`типові_поля`),
    # не їхали фактом її дня моделям, але правила рахували ними, як її словами: +18 °C знімали
    # з пулу всі босоніжки й сандалі (0 у 40 з 40 прогонів розбору, 159–292 пари на
    # прогін), 11:00 вмикали `day_outing` на новорічному корпоративі, а місце плитки
    # «весілля вечірнє» стояло над її «весіллям удень». ЩО ТЕПЕР (п.12: «невідомо» замість
    # вигадки). Поле з переліку лишається, лише коли паспорт несе його зі слів — її чи
    # почутих моделлю (`джерело_полів` не `типове_форми`); інакше його в нагоді нема: відсів
    # за ним не працює, вісь «день/вечір» не вмикається, а модель бачить «невідомо».
    _дж = п.get("джерело_полів") or {}
    # Явне відхилення саме sport-нагоди сильніше за стару плитку; ключ тлумачить паспорт
    if плитку_відхилено(п, нагода.get("нагода")):
        нагода.pop("нагода", None)
    # Без показу (`типові_поля` нема — стенд, CLI) замовчування форми називає мітка паспорта `типове_форми`: інакше
    # її +18 °C і 11:00 стояли б тут її словами й їхали б рукам погодою
    _типові = (типові_поля_форми(с) if "типові_поля" in с
               else tuple(k for k in типові_з_форми(п) if k in _ПОГОДА.ПОЛЯ))
    for k in _типові:
        if п.get(k) in (None, "", "невідомо") or _дж.get(k) == ТИПОВЕ_ПОЛЕ_ФОРМИ:
            нагода.pop(k, None)
    # Пора року — завжди відома: з місяця події, коли вона його назвала, інакше з дати
    # сьогодні; та, що вже стоїть у сценарії чи паспорті, — як є
    нагода.setdefault("пора_року", _ПОГОДА.пора_року_події(нагода.get("місяць"), _ПОГОДА.сьогодні()))
    # Відчуття без градусів — число для правил (`сценарій.темп_для_правил`); ДО опадів: «так» при морозі — сніг
    if нагода.get("темп_c") in (None, "") and нагода.get("погода_відчуття") not in (None, ""):
        _т = _ПОГОДА.темп_для_правил(нагода)
        if _т is not None:
            нагода["темп_c"], нагода["темп_з_відчуття"] = _т, True
    # Пора без години — година для правил (`сценарій.година_для_правил`); названа година пору знімає
    if нагода.get("година") in (None, ""):
        _г = _ПОГОДА.година_для_правил(нагода)
        if _г is not None:
            нагода["година"], нагода["година_з_пори"] = _г, True
    else:
        нагода.pop("пора", None)
    # Опади — єдине поле, де два джерела говорять РІЗНОЮ ТОЧНІСТЮ (див. вище).
    # Канон ставиться навіть тоді, коли паспорт мовчить: далі по шву стоять
    # споживачі («нема» плитки проти «ні» композитора), і слово має бути одне.
    if "опади" in нагода or п.get("опади") not in (None, ""):
        _оп = _ПОГОДА.опади_поверх(с.get("опади"), п.get("опади"), нагода.get("темп_c"))
        if _оп is None:
            нагода.pop("опади", None)
        else:
            нагода["опади"] = _оп
    # Вітер — бал шкали показу в м/с, і рівно тут (П-1, абзац над `ВІТЕР_БАЛИ`).
    _бал = нагода.pop("вітер_бал", None)
    if нагода.get("вітер") in (None, ""):
        _мс = _ПОГОДА.вітер_мс(_бал)
        if _мс is not None:
            нагода["вітер"] = _мс
    # Дія й поверхня під ногами — лише полем паспорта (`активність`, `поверхня`), яке ставить
    # мовна модель шару кодами `activity` / `surface` на уривку її слів (Ч-4, див. нижче).
    return нагода, sorted(незнайомі)

