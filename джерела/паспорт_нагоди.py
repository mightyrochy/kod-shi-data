def промпт_паспорта(сценарій, слова, профіль_текст="", історія=None, паспорт=None, драп=None, фото=None):
    """Виклик 0: сценарій + слова людини (+ розмова й паспорт досі) → JSON, який читає
    код. Не вигадувати (K-IO-02): чого людина не сказала — «невідомо», а код бере
    значення з обраного сценарію.

    ── ЧАТ ЗАПОВНЮЄ ТОЙ САМИЙ ПАСПОРТ (Т-08 крок 1) ─────────────────
    Доти промпт був одноразовим перекладом: плитки + одне поле слів → JSON, і
    другого слова жінці не належало. Тепер він приймає `історія`
    ([{"хто": "людина|ші", "текст": …}]) і `паспорт` (частковий — з попередньої
    відповіді або з плиток) і просить повернути ПОВНИЙ паспорт: що відомо —
    заповнене, чого не сказано — «невідомо»/null, а для обовʼязкових порожніх
    полів (нагода, місце, дрес-код або їхній еквівалент словами) —
    `питання_людині`. Ключі нагод/місць/кодів модель бачить із того самого
    `довідник()`, з якого малюються плитки: «побачення в ресторані» стає
    `нагода=побачення, місце=ресторан_районний`, і плитки показують стан
    паспорта, а не окремий від нього вибір. Одне джерело істини
    (`СХЕМА_ПАСПОРТА`), один парсер (`паспорт_з_json`).

    ── ФОТО РЕЧІ ────────────────────────────────────────────────────
    `фото` — фото речей НОВОЇ репліки ([{ід, ширина, висота}]); самі зображення їдуть
    у тому самому виклику моделі блоками перед текстом. Промпт тоді додає поле
    «фото_речей» (з його рядком) і схему речі до схеми відповіді.

    ── ОГОЛОШЕННЯ ЗБИРАЧА ─────────────────────────────────────────
    Промпт — `збирач_промптів.зібрати(ПАСПОРТ, дані)`: у ньому лише поля, які цей
    виклик несе, їхні рядки, правила задачі, загальні межі й скелет останнім."""
    сц = сценарій or {}
    дані = {}
    # ЗАМОВЧУВАННЯ ФОРМИ НЕ СТОЇТЬ У «ОБРАНО» (В-2): рядок цього поля каже моделі «що
    # вона обрала плитками», і вшиті 11:00 та 18 °C їхали в нього нарівні з її вибором.
    # Число не ховаємо — воно їде окремим полем із позначкою «вона цього не називала»,
    # і модель бачить, що видавати його їй за факт не можна.
    _типові_ф = типові_поля_форми(сц)
    _обрано = {k: сц.get(k) for k in ("нагода", "місце", "дрес_код", "година", "темп_c")
               if сц.get(k) not in (None, "") and k not in _типові_ф}
    _мк_плитка = макіяж_канон(сц.get("макіяж"))
    if _мк_плитка and "макіяж" not in _типові_ф:
        _обрано["макіяж"] = _мк_плитка
    дані["обрано"] = _обрано
    _типове = {k: сц.get(k) for k in _типові_ф if сц.get(k) not in (None, "")}
    if _типове:
        дані["типове_не_назване"] = _типове
    _пасп = паспорт if isinstance(паспорт, dict) else {}
    if _пасп:
        _досі = {k: v for k, v in _пасп.items()
                 if (k in СХЕМА_ПАСПОРТА or k in ПОЛЯ_ПОЗА_СХЕМОЮ_ПАСПОРТА)
                 and k not in ПОЛЯ_ЧАТУ_ПАСПОРТА and k not in _ПОЛЯ_ЛИШЕ_КОДУ}
        if (_пасп.get("джерело_полів") or {}).get("нагода") == ТИПОВА_НАГОДА_РЕЧІ:
            # типова нагода речі з фото — не її слова: модель її не бачить,
            # інакше повернула б як сказане, і мітка «типово» зникла б на другому ході
            _досі.pop("нагода", None)
        # ТА САМА ПРИЧИНА ДЛЯ ЗАМОВЧУВАНЬ ФОРМИ (В-2): вони вже стоять окремим полем
        # «типове_не_назване», і другий раз — усередині паспорта досі, без позначки —
        # модель прочитала б їх як сказане, і мітка зникла б на другому ході.
        for _тф in типові_з_форми(_пасп):
            _досі.pop(_тф, None)
        if _досі.get("речі_з_фото"):
            # речі з фото — СЛОВАМИ (колір виміру, вердикт коду реченням), без чисел виміру
            _досі["речі_з_фото"] = [_РФ_.для_моделі(х) for х in _досі["речі_з_фото"] if isinstance(х, dict)]
        дані["паспорт_досі"] = _досі
    # ЯВНИЙ ДОТИК РУКИ НАЗИВАЄТЬСЯ ВГОЛОС: модель, яка читає «її слова переважають», інакше
    # повертає стару нагоду з розмови; код однаково перебиває поле, а пояснення лишається чесним.
    _рукою = поля_рукою(сц, _пасп)
    if _рукою:
        дані["змінено_рукою"] = {k: сц.get(k) for k in _рукою}
    # РОЗМОВА — ВІКНОМ І ЗВЕДЕННЯМ (константи й причина — над оголошенням).
    _репліки, _раніше = вікно_розмови(історія)
    if _репліки:
        дані["розмова"] = _репліки
    if _раніше:
        дані["розмова_раніше"] = _раніше
    elif str(слова or "").strip():
        # розмова вже несе її останню репліку — друге поле з тими самими словами лише подвоїло б її
        дані["її_слова"] = str(слова).strip()
    # `профіль_текст` показ у виклик 0 не шле (`показ.html`, `містП('паспорт', база)`): поля нема.
    _драп = dict({k: v for k, v in (_пасп.get("драп_сирий") or {}).items() if v},
                 **{k: v for k, v in (драп if isinstance(драп, dict) else {}).items() if v})
    assert not питати_драп()     # драпіровка — лише профіль (Р-3): у розмові не питається
    # Відповіді драпіровки код зливає сам (`паспорт_з_json`, `драп`), і питати їх заборонено (Р-3):
    # моделі вони не потрібні — поля нема.
    # ФОТО РЕЧІ: що назвати й чого не казати — у рядку поля. Її речі словами
    # код із її слів більше не виймає (Ч-4): їх дає лише мовна модель шару.
    if фото:
        дані["фото_речей"] = [str(ф.get("ід")) for ф in фото]
    _є_річ = bool(фото or _пасп.get("речі_з_фото"))
    if _є_річ:
        дані["списки_речі"] = _РФ_.списки()
    дані["ключі"] = {"нагода": ключі_довідника("нагоди"), "місце": ключі_довідника("місця"),
                     "дрес_код": ключі_довідника("коди"), "реєстр_людини": ключі_реєстрів()}
    _порада = порада_коду(сц, _пасп, слова, драп=_драп or None, є_річ=_є_річ)
    if _порада:
        дані["теми_поради"] = list(_порада["підказки"])
    о = ПАСПОРТ
    if _є_річ:
        import dataclasses as _dc
        о = _dc.replace(ПАСПОРТ, скелет=dict(СХЕМА_ПАСПОРТА, речі_з_фото=[_РФ_.СХЕМА_РЕЧІ]))
    # Текст для неї (відповідь, питання, порада) і її слова в полях — українською: виклик 0 іде
    # без мовного шару, перекладати нікому (`збирач_промптів.зібрати`, `мова_тексту`).
    return _json_.dumps(_ЗП_.зібрати(о, дані, мова_тексту="Ukrainian"), ensure_ascii=False)


def паспорт_з_json(текст, сценарій, слова, вето_чипів=None, паспорт_досі=None, драп=None, фото=None,
                   словами=None, чекати_відповідь=True, шар=False):
    """JSON моделі → паспорт із дефолтами з обраного сценарію. Модель мовчить або
    бреше форматом → паспорт будується з того, що обрала людина, і це видно у `джерело`.

    ── ПАСПОРТ БЕЗ МОВЧАЗНИХ ДЕФОЛТІВ (Т-09) ────────────────────────
      before — невдалий розбір мовчки віддавав дефолти сценарію: ПРИЧИНИ не лишалось
               (другій спробі нічого сказати моделі), а межі людини — `вето.зони` і
               все, що з них робить `bridge._застосувати_паспорт` (`жорстке_ні`), —
               гинули разом із відповіддю. Найсильніше, що людина сказала, не
               доїжджало до правил, і виглядало це так, ніби доїхало.
      after  — причина має ім'я (`помилка_формату`), а зони, поставлені ЧИПАМИ на
               екрані нагоди, лежать у паспорті в ОБОХ гілках і об'єднуються з тим,
               що назвала модель: обидва списки — про те, чого людина не хоче, тож
               суворіший виграє. Типи/тканини/принти/кольори з її слів код доти
               дописував сам словниками (Н-V07-023); з Ч-4 її слова
               читає лише мовна модель шару, тож без відповіді моделі цих меж нема —
               «невідомо», а не словник (див. `НЕВІДОМІ_БЕЗ_ШАРУ`).

    ── ПАСПОРТ ДОСІ ЇДЕ В РОЗБІР, А НЕ ЛИШЕ В ПРОМПТ ─
      before — розбір бачив лише відповідь моделі й плитки. Відповіді про
               драпіровку, яких схема моделі не оголошує, жили один хід; а явна
               дія руки над плиткою програвала здогаду моделі про те саме поле.
      after   — `драп_сирий` ходу 1 лежить у паспорті ходу 2 (нову відповідь
               моделі він не затирає: свіже слово перемагає поключово), а поля,
               які жінка змінила рукою після того паспорта (`поля_рукою`),
               ставляться з плиток поверх моделі. Що саме перемогло, видно в
               `джерело_полів`: her або conversation, а не мовчазна підміна.

    ── СЛАБКА МОДЕЛЬ: КОПІЯ ДОВІДНИКА Й ВЛАСНЕ «НЕВІДОМО» ─
      Обидві дірки виміряні живою qwen3-vl-8b на 16 вільних текстах.
      before — `"нагода": "робота — Робота (зустріч, …)"` (модель скопіювала рядок
               промпта цілком) не був ключем → `нагода=None` і зайве питання жінці
               «не знаю такої нагоди», хоч ключ стояв у самому значенні; а поле, яке
               модель САМА назвала в «невідомо», усе одно читалось — `"мета":
               "лестити"` з `"невідомо": ["мета"]` (5 із 12 текстів) доїжджала до
               рангу основ і `чому_мети` як справжня мета жінки.
      after  — `ключ_довідника` зводить значення до ключа, коли ключ або підпис у
               ньому вже стоїть (незнайоме слово й далі стає питанням), а
               `поля_названі_невідомими` викидає відповідь про такі поля ДО читання:
               лишається те, що було б без моделі — плитка, `паспорт_досі`, дефолт.

    ── РЕЧІ З ФОТО ─────────────────────────────────────────────────
      `фото` — нові фото цієї репліки. Речі з фото лежать у паспорті в ОБОХ гілках
      (провал JSON не має права коштувати фото, яке вона вже надіслала), а коли вона
      спитала про річ і не назвала ні нагоди, ні місця, ні рівня ошатності, нагода
      стає «щоденне» з міткою `ТИПОВА_НАГОДА_РЕЧІ` у `джерело_полів`: річ судиться й
      збирається на звичайний день, і це видно, а не мовчки підставлено.

    ── МОВНИЙ ШАР (рішення власника) ─────────────────────────────────
      `словами` — її речі словами, уже прочитані перекладачем (`річ_з_фото.її_речі_шару`).
      `None` — їх нема: зі `слова` код їх не виймає (Ч-4).
      `чекати_відповідь=False` — цей виклик речення для жінки в моделі не просив
      (переклад внутрішньої мови: репліку складає код), тож відсутність
      «відповідь_людині» тут не провал і повтору не вимагає (В-12).

    ── ЇЇ СЛОВА КОД НЕ ЧИТАЄ (Ч-4, аудит/ПРОДУКТ.md п.12) ─────────────────────
      `шар=True` — відповідь склав шов мовного шару (`мовний_шар.паспорт_з_шару`) з кодів
      перекладача, і кожне поле вже стоїть на дослівному уривку її слів: береться все.
      `шар=False` — це модель виклику 0: поля, які доти тримав лише словник її слів
      (межі-типи, тканини, принти й зони моделі, формат, місце, числа дня, реєстр),
      — «невідомо»; що саме не взято, каже `не_взято_кодом` (звіт власника). `слова`
      лишаються в паспорті її текстом для моделей і звіту — код їх не читає.
    """
    сц = dict(сценарій or {})
    from паспорт_поля import чинний_ключ
    сц = {к: чинний_ключ(к, в) for к, в in сц.items()}
    _досі_п = мета_на_осі(паспорт_досі) if isinstance(паспорт_досі, dict) else {}
    _досі_п = {к: чинний_ключ(к, в) for к, в in _досі_п.items()}
    _досі_п = dict(_досі_п, джерело_полів={к: _СТ.автор(v) for к, v in (_досі_п.get("джерело_полів") or {}).items()})
    _драп_досі = {k: v for k, v in (_досі_п.get("драп_сирий") or {}).items() if v}
    _рукою = поля_рукою(сц, _досі_п)
    _типові_ф = типові_поля_форми(сц)      # В-2: поля, яких рука не торкалась
    _чипи = sorted({str(z).strip().lower() for z in ((вето_чипів or {}).get("зони") or [])}
                   & set(ЗОНИ_ВЕТО))
