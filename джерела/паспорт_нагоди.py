def вид_нагоди(ключ):
    """Ключ нагоди ядра → (вид події, пресет вимірів). Незнайомий ключ → (None, {}).

    Сам ключ теж приймається видом: НГ-4 дасть моделі ставити `вид` напряму, і тоді в
    паспорті стоятиме вже код (`wedding`), а не ключ ядра (`весілля_гість`)."""
    к = str(ключ or "").strip()
    if к in ПСЕВДОНІМИ_НАГОДИ:
        вид, пресет = ПСЕВДОНІМИ_НАГОДИ[к]
        return вид, dict(ВИДИ_НАГОДИ.get(вид) or {}, **пресет)
    if к in ВИДИ_НАГОДИ:
        return к, dict(ВИДИ_НАГОДИ[к])
    return None, {}


def _звідки_поля(п, поле):
    """Позначка `звідки` для значення, яке ВЖЕ стоїть у паспорті під цим полем.

    Замовчування форми (11:00, +18 °C, яких вона не називала) і типова нагода речі з фото —
    це `default`, а не її слова: та сама межа, яку вже тримають `ТИПОВЕ_ПОЛЕ_ФОРМИ` і
    `ТИПОВА_НАГОДА_РЕЧІ`. Усе інше в паспорті стоїть з її вибору — рукою на плитці чи
    словом у розмові (`джерело_полів` тримає, чим саме), і це `her_words`.
    `written` тут не зʼявляється й зʼявитись не може: паспорт ще не має поля «це написано в
    запрошенні» — його дасть мовна модель (НГ-4), і сила джерела вже оголошена під нього."""
    м = (п.get("джерело_полів") or {}).get(поле)
    return "default" if м in (ТИПОВЕ_ПОЛЕ_ФОРМИ, ТИПОВА_НАГОДА_РЕЧІ) else "her_words"


def виміри_нагоди(паспорт=None, сценарій=None):
    """(виміри, звідки) — паспорт нагоди v2: подія вимірами кодами й сила джерела кожного.

    Виміри — єдиний вихід: словник `вимір → код` (усі оголошені виміри стоять завжди), і
    `звідки` з тими самими ключами. «Невідомо» — рядок "unknown" для виміру з переліком і
    `None` для числового; `звідки` тоді теж "unknown".

    ПОРЯДОК СИЛИ ДЖЕРЕЛ (§1.2, `ЗВІДКИ_СИЛА`): письмове правило → її слова → пресет
    підпункту → пресет виду → пресет найближчого виду для «Іншого» → типове коду →
    невідомо. Сильніше джерело перебиває слабше, і в НГ-1 працюють чотири з семи:
    `her_words` (паспорт і плитки), `preset` (вид), `like` («Інше»), `default` (типове).
    `written` і `sub` оголошено під НГ-4 і НГ-5 — полів під них у паспорті ще нема.

    Код за цими вимірами НІЧОГО НЕ РАХУЄ: читачі приходять у НГ-2 (пул, суд) і НГ-3 (пакет
    стилістці). Доти це запис того, що система про подію знає, для журналу й звіту власника."""
    import внутрішня_мова as _ВМ, сценарій as _СЦ
    п = паспорт if isinstance(паспорт, dict) else {}
    сц = сценарій if isinstance(сценарій, dict) else {}
    виміри = {в: _ВМ.UNKNOWN for в, _, _ in ПОЛЕ_ВИМІРУ}
    виміри.update({в: None for в, _ in ЧИСЛО_ВИМІРУ})
    виміри.update(part_of_day=_ВМ.UNKNOWN, formality=None, makeup_level=_ВМ.UNKNOWN, parts=[])
    звідки = {в: _ВМ.UNKNOWN for в in виміри}

    def став(вимір, значення, джерело):
        """Ставить вимір, лише якщо джерело не слабше за те, що вже стоїть."""
        if значення in (None, "", [], _ВМ.UNKNOWN):
            return
        if ЗВІДКИ_СИЛА.index(джерело) >= ЗВІДКИ_СИЛА.index(звідки[вимір]):
            return
        виміри[вимір], звідки[вимір] = значення, джерело

    # 1. ЇЇ СЛОВА Й ЇЇ ПЛИТКИ: те, що вже стоїть у паспорті (а поза паспортом — у сценарії).
    for вимір, поле, ключ in ПОЛЕ_ВИМІРУ:
        if not ключ:
            continue
        сире = п.get(ключ) if п.get(ключ) not in (None, "", "невідомо") else сц.get(ключ)
        if сире in (None, "", "невідомо"):
            continue
        # опади в паспорті бувають грубим «так» — канон зводить їх до слова переліку
        if ключ == "опади":
            сире = _СЦ.канон_опади(сире, п.get("темп_c") or сц.get("темп_c"))
        elif ключ == "рух":
            сире = РУХ_ЯДРА_У_ВИМІР.get(str(сире).strip(), сире)
        код = _ВМ.код(поле, сире) or (str(сире) if str(сире) in _ВМ.ТАБЛИЦЯ[поле] else None)
        став(вимір, код, _звідки_поля(п, ключ))
    for вимір, ключ in ЧИСЛО_ВИМІРУ:
        сире = п.get(ключ) if п.get(ключ) not in (None, "") else сц.get(ключ)
        try:
            став(вимір, float(сире) if вимір != "hour" else int(float(сире)), _звідки_поля(п, ключ))
        except (TypeError, ValueError):
            pass
    _о = п.get("ошатність") or сц.get("ошатність")
    if isinstance(_о, (list, tuple)) and len(_о) == 2:
        став("formality", [int(_о[0]), int(_о[1])], _звідки_поля(п, "ошатність"))
    _мк = макіяж_канон(п.get("макіяж") or сц.get("макіяж")) or {}
    став("makeup_level", _ВМ.код("makeup_level", _мк.get("рівень")), _звідки_поля(п, "макіяж"))
    if виміри["hour"] is not None:
        став("part_of_day", _СЦ._частина_доби(виміри["hour"] % 24), звідки["hour"])
    # Частини дня (§2): 1–3 частини одного виходу, «вінчання → банкет». Поля ще нема в
    # паспорті — його дасть НГ-4; типове — одна частина, сам вид.
    _ч = [_ВМ.код("event_kind", x) or (str(x) if str(x) in _ВМ.ТАБЛИЦЯ["event_kind"] else None)
          for x in (п.get("частини_дня") or [])]
    _ч = [x for x in _ч if x][:3]
    if _ч:
        став("parts", _ч, "her_words")

    # 2. ВИД: з поля `вид` (його дасть НГ-4 — там уже КОД) або з нинішнього КЛЮЧА ЯДРА
    # нагоди через псевдонім. Ключ ядра, а не код виміру `occasion`: псевдоніми названі
    # ключами, якими нагода жила доти («весілля_гість»), і саме в цьому їхня робота.
    _кл = str(п.get("нагода") or сц.get("нагода") or "").strip()
    вид, пресет = вид_нагоди(п.get("вид"))
    if вид:
        став("kind", вид, "her_words")
    else:
        вид, пресет = вид_нагоди(_кл)
        if вид:
            став("kind", вид, _звідки_поля(п, "нагода"))
    # 3. ПРЕСЕТ ВИДУ, а для «Іншого» — пресет найближчого виду (`like`).
    for ім, зн in sorted(пресет.items()):
        став(ім, зн, "preset")
    if виміри["kind"] in (_ВМ.UNKNOWN, "other"):
        _лайк, _пресет_л = вид_нагоди(виміри["like"] if виміри["like"] != _ВМ.UNKNOWN else None)
        for ім, зн in sorted(_пресет_л.items()):
            став(ім, зн, "like")
    if виміри["kind"] != _ВМ.UNKNOWN and not виміри["parts"]:
        став("parts", [виміри["kind"]], "default")
    # 4. ТИПОВЕ КОДУ — останнім: припущення, назване припущенням.
    for ім, зн in sorted(ТИПОВЕ_ВИМІРУ.items()):
        став(ім, зн, "default")
    return виміри, звідки



