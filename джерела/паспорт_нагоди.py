def _стан_для_поради(сц, пасп, слова):
    """Одне поле = плитка або паспорт досі, хто що знає: код читає СТАН, а не джерело."""
    п, с = (пасп or {}), (сц or {})
    def _з(k):
        """Значення поля з паспорта досі, а коли там порожньо/«невідомо» — з плитки."""
        v = п.get(k)
        return v if v not in (None, "", "невідомо", [], {}) else с.get(k)
    текст = " ".join(str(x or "") for x in (слова, п.get("подія"), с.get("подія")))
    година = _з("година")
    try: година = int(float(година)) if година not in (None, "") else None
    except (TypeError, ValueError): година = None
    return dict(нагода=_з("нагода"), місце=_з("місце"), година=година, темп_c=_з("темп_c"),
                формат=_з("формат"), рух=_з("рух"), тривалість=_з("тривалість_год"),
                мета=_з("мета"), макіяж=макіяж_канон(_з("макіяж")), прикраси=_з("прикраси"),
                реєстр=_з("реєстр_людини"), фото=bool(_ПОДІЯ_ФОТО.search(текст)))


