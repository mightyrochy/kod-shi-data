    # Це ті самі ключі, з яких малюються плитки: відомий ключ переважає плитку
    # (слова людини — перші), невідомий не підставляється сусіднім словом і не
    # гине мовчки — плитка лишається як була, а слово моделі йде рядком у звіт
    # власника. ПИТАННЯ СЛОВАМИ КОДУ ЇЙ НЕМА (Ч-4, кошик В): доти код сам писав їй
    # ««…» — не знаю такої нагоди; обери з плиток або опиши інакше»; речення для неї
