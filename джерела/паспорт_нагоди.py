    вечір = ((ст["година"] is not None and ст["година"] >= 18) or ст["нагода"] in ВЕЧІРНІ_НАГОДИ
             or ст["місце"] in ВЕЧІРНІ_МІСЦЯ or ст["фото"])
    надворі = ст["формат"] in ("просто неба", "змішано") or ст["місце"] in ПРОСТО_НЕБА_МІСЦЯ
    _метал_профілю = (драп or {}).get("метал") if isinstance(драп, dict) else None
