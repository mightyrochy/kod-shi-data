# колір, обсяг і `письмово` — які з полів написано в запрошенні чи правилах місця. Таблиця
# `ПОЛЯ_ВИМІРІВ_РОЗМОВИ` — ЄДИНА відповідність «ключ паспорта → поле розмови → перелік»: її
# читають шов розмови (`мовний_шар.паспорт_з_шару`), паспорт кодами для моделі
