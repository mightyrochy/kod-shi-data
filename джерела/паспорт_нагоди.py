    таблиці["поля_паспорта"] = поля_показу()
    таблиці["причини_ошатності"] = [dict(ключ=к, підпис=п) for к, п in (
        ("written", "письмова вимога"), ("norm", "норма місця чи людей"),
        ("evaluated", "+1, її оцінюють"), ("representing", "+1, вона представляє"),
        ("her_words", "її слова"))]
    return таблиці


