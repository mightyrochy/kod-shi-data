def слова_вето(слово):
    """Слово вето людини → основи для `profile.жорстке_ні_фільтр`: саме слово плюс
    основи його класу, коли клас у режимі «вето». Незнайоме слово — як є."""
    к = str(слово or "").strip().lower()
    if not к:
        return []
    з = ВЕТО_СЛОВА.get(к)
    return [к] + ([w for w in з["слова"] if w != к] if з and з["режим"] == "вето" else [])


# ── ТИПИ/ТКАНИНИ/ПРИНТИ/КОЛЬОРИ СЛОВАМИ — ЗАПАСНИЙ ШЛЯХ ПОЗА JSON (Н-V07-023) ──
# ЗОНИ вже не залежать від відповіді моделі: чипи екрана нагоди зливаються в
# `вето.зони` в ОБОХ гілках `паспорт_з_json` (Т-09, нижче в цьому файлі). Чотирьох
# інших осей вето це не стосувалось: провал JSON (порожня відповідь, «```» без
# тіла, капризний формат) забирав їх мовчки, і «не ношу шкіру, леопард і рожеве,
# спідниці ніколи» гинуло разом із форматом — той самий обмін «мовчазний дефолт
# замість причини», який Т-09 уже закрив для зон, тут лишався відкритим.
# СЛОВНИКИ — ТІ САМІ, ЩО ВЖЕ ЧИТАЄ ЖИВИЙ ШЛЯХ, А НЕ НОВИЙ СПИСОК СЛІВ: типи —
# `feed.ТИП_КЛЮЧІ` (те саме, що перевіряє `feed.тип_речі`; результат лягає в
# поле `тип` речі), тканини — `verify.волокно_зі_слова` (лягає в `волокно`),
# принти — `verify.клас_мотиву` (лягає в `візерунок`; «однотонний» перекладено в
# «solid», бо саме це слово лежить у записі речі — інакше вето на «однотонний»
# не збіглося б НІКОЛИ, мовчки), кольори — `verify.назва_кольору` (лягає в
# `колір_назва`). Усі чотири поля — у `profile._СЛОВА_РЕЧІ`, тож слово звідси
# доїжджає до того самого фільтра, що й слово від моделі (bridge.py:979-982
# ганяє обидва джерела через `слова_вето` в один і той самий `жорстке_ні`).
# Незнайоме слово — НЕ вето (K-IO-02): «оксамитова душа» без кореня жодного зі
# словників не додає нічого, і це чесна тиша, а не пропуск.
_ЗАПЕРЕЧЕННЯ_ВЕТО = re.compile(r"не\s+но[сш]\w*|\bніколи\b|\bбез\b|жорстк\w*\s*ні\b", re.I)
_МЕЖА_РЕЧЕННЯ_ВЕТО = re.compile(r"[.!?;\n]+")


def вето_поза_зонами_зі_слів(текст):
    """Слова людини → dict(типи=[…], тканини=[…], принти=[…], кольори=[…]).

    Межа читання — РЕЧЕННЯ (крапка/«!»/«?»/«;»/новий рядок), НЕ кома: «не ношу
    шкіру, леопард і рожеве» — один подих одним запереченням на трьох речах, і
    кома його не розриває. Речення без жодного слова заперечення («не ношу»,
    «ніколи», «без», «жорстке ні») не читається зовсім — «хочу леопардовий
    принт» не несе жодного з чотирьох і мовчить, як і мусить (K-IO-02).

    ЧЕСНО ПРО МЕЖУ РЕЧЕННЯ: сполучник «але» посередині зачепленого речення
    («не ношу шкіру, але люблю замшу») сьогодні не звужує його — замша
    потрапила б у той самий список. Той самий рід ризику, який
    `profile.жорстке_ні_фільтр` уже називає навмисним («хибне спрацювання
    коштує однієї речі, пропуск — довіри»); звужувати межу до сполучників —
    наступний наряд, коли знайдеться жива фраза, а не здогад про неї."""
    import feed as _Ф
    import verify as _В
    вих = dict(типи=[], тканини=[], принти=[], кольори=[])
    for речення in _МЕЖА_РЕЧЕННЯ_ВЕТО.split(str(текст or "").lower()):
        if not речення.strip() or not _ЗАПЕРЕЧЕННЯ_ВЕТО.search(речення):
            continue
        т = _Ф._re_тип.sub(" ", речення)
        for тип, ключі in _Ф.ТИП_КЛЮЧІ:
            if тип not in вих["типи"] and any(k in т for k in ключі):
                вих["типи"].append(тип)
        волокно = _В.волокно_зі_слова(речення)
        if волокно and волокно not in вих["тканини"]:
            вих["тканини"].append(волокно)
        мотив = _В.клас_мотиву(речення)["клас"]
        if мотив:
            мотив = "solid" if мотив == "однотонний" else мотив
            if мотив not in вих["принти"]:
                вих["принти"].append(мотив)
        колір = _В.назва_кольору(речення)
        if колір and колір not in вих["кольори"]:
            вих["кольори"].append(колір)
    return вих


