    # Ті самі входи, що в промпті (сценарій, паспорт досі, слова) → та сама ГРУПА тем;
    # коли модель СКАЗАЛА пораду, УСІ теми ходу лягають у `поради_дані` разом і
    # незалежно від того, чи модель кожну з них вдягла в слова, — одне ігнорування, і
    # вдруге не пропонуємо. Інакше тема, яку модель пропустила як таку, що не в'яжеться
    # в речення, верталась би щоходу й робила з поради анкету. Слова моделі без тем від
    # коду не показуються: інакше «без повторів» тримала б модель. Стеля 400 символів
    # (а не 300) — бо речень тепер два і вони несуть до трьох тем; промпт просить ~350.
    #
    # ПОРОЖНЯ ПОРАДА МОДЕЛІ ТЕМ НЕ СПАЛЮЄ (рядок 160(б), 27.09.2026). Доти теми ходу
    # лягали в `поради_дані` й тоді, коли модель не сказала НІ СЛОВА: `порада_людині`
    # лишалась порожньою, жінка запрошення не бачила — а код уже вважав теми
    # запропонованими й удруге їх не пропонував. Виміряно на РЕАЛЬНОМУ паспорті Ір
    # («вигуляти собак», gemma, сід 13, `аудит/тести/сирі_2026-09-25/p4_ir_sobaky_gemma_seed13`,
    # де `"порада_людині": ""`): одним ходом згоряли `рух`, `температура` і `прикраси` —
    # три з шести доречних тем, тобто ворота взуття, тканина й шар лишались сліпими
    # назавжди, бо наступний хід уже пропонував лише `реєстр`. Це та сама межа, яку
    # гілка `порада_відкинуто` нижче вже тримала: «ігнорувати непоказане вона не могла».
    # Проба: `проби/porada_pusta_160b.py`.
    _порада = порада_коду(сц, _досі_п, слова,
                          драп=(dict(_драп_досі, **(драп if isinstance(драп, dict) else {})) or None),
                          є_річ=_є_річ)
    if _порада:
        п["поради_дані"] = _дані + list(_порада["теми"])
        if str(об.get("порада_людині") or "").strip():
            # ФОРМУ ТРИМАЄ КОД, НЕ ПРОМПТ (З-3): порада-питання не показується. Свого
            # речення код їй не пише (Ч-4, кошик В) — тож теми цього ходу вона не почула, і
            # вони не рахуються даними: наступний хід запропонує їх знову (п.9 — «без
            # повторів після ігнорування», а ігнорувати непоказане вона не могла).
            _чиста, _чому = порада_чиста(жінці(str(об["порада_людині"]).strip()[:400]),
                                         _порада["теми"])
            п["порада_людині"] = _чиста
            if _чому:
                п["поради_дані"] = list(_дані)
                # НЕ ковтати мовчки (п.14) — і НЕ в `питання_людині`: той список
                # іде на екран жінці, а це слід для звіту власника. Ключ ходовий,
                # як `поради_дані`: у схемі паспорта його нема, у пакет моделі не
                # їде (`випадок_для_пакета` бере лише поля ВИПАДКУ).
                п["порада_відкинуто"] = dict(
                    причина=_чому, було=str(об["порада_людині"]).strip()[:400],
                    стало=_чиста, теми=list(_порада["теми"]))
        else:
            # Модель промовчала: теми вертаються в чергу (їх ще не чули). Слід — ходовим
            # ключем, як `порада_відкинуто` вище, а НЕ в `не_взято_кодом`: той список іде
            # в діагноз збирання рядок у рядок, а цей слід живе один хід (наступний хід
            # ті самі теми пропонує знову, і рядок про «не взято» був би неправдою).
            п["поради_дані"] = list(_дані)
            п["порада_не_озвучена"] = dict(
                причина="модель віддала порожнє «порада_людині»", теми=list(_порада["теми"]))
    # ── ЧИСЛО ДНЯ ВІД МОДЕЛІ ВИКЛИКУ 0 — «НЕВІДОМО» (Ч-4) ─────────────────────
    # Доти число моделі брала опора в її словах (рядок 209: регулярки погоди, години,
    # тривалості й числа словами), а своє прочитане число код ставив поверх. Числа з її
    # слів дає лише шар (`hour`, `temperature_c`, `duration_h` на уривку); без нього
    # лишається плитка, а що не взято — рядком у звіт власника, не жінці.
    for k in ("тривалість_год", "година", "темп_c"):
        if об.get(k) in (None, ""):
            continue
        if not шар:
            п.setdefault("не_взято_кодом", []).append(
                "not_taken · step=call0 · field=%s · model_said=%s · reason=no_language_layer · kept=%s"
                % (k, _json_.dumps(об.get(k), ensure_ascii=False),
                   _json_.dumps(сц.get(k), ensure_ascii=False) if сц.get(k) not in (None, "") else "unknown"))
            continue
        try:
            п[k] = float(об[k]) if k != "година" else int(об[k])
        except (TypeError, ValueError):
            pass
    # ── МАКІЯЖ ЗІ СЛІВ — ТИМ САМИМ КАНОНОМ, ЩО ПЛИТКА (рядок 108) ─────────────
