# ── ПЕРЕЛІК ІЗ ПРОМПТА НЕ Є ВІДПОВІДДЮ (розбір 1/8, В-11, 26.09.2026) ──────────
# ЩО ВИДНО: `{"рух": "сидіти | ходити", "формат": "приміщення | просто неба"}` — модель
# повернула сам РЯДОК СХЕМИ замість одного його члена, а код брав його як є, і в
# паспорті стояв «рух = сидіти | ходити». Руки 3–4 читають це рядком випадку як факт
# її дня, і `не_взято_кодом` про це не казав нічого.
# ЧОМУ ЦЕ КОД, А НЕ МОВА: перелік оголошено тут-таки, у `СХЕМА_ПАСПОРТА`, і звірка —
# рівність із його членом, а не тлумачення слова. Другого списку значень нема й не буде:
# розійшовся б зі схемою на першій правці.
def перелік_схеми(поле):
    """Члени переліку цього поля зі `СХЕМА_ПАСПОРТА` («сидіти | ходити | …») або ().

    Нота члена до нього не входить: у промпті вона пояснює моделі, що значить ключ
    («comfort_first — просить зручності», «етно = дерево, кістка»), а відповідь —
    сам ключ."""
    опис = str(СХЕМА_ПАСПОРТА.get(поле) or "")
    if "|" not in опис:
        return ()
    члени = (re.split(r"\s*[(—–]", х.strip(), maxsplit=1)[0].strip() for х in опис.split("|"))
    return tuple(ч for ч in члени if ч)


def значення_схеми(поле, значення):
    """Відповідь моделі → член переліку поля, або None, коли це не він."""
    в = " ".join(str(значення or "").split()).strip(" .,;:«»\"'").lower()
    if not в:
        return None
    return next((ч for ч in перелік_схеми(поле) if ч.lower() == в), None)


def _це_unknown(в):
    return isinstance(в, str) and в.strip().lower() == "unknown"


def невідомо_схеми(вузол):
    """«unknown» від моделі англійського шаблону → «невідомо» схеми паспорта (Ч-4, п.12).

    Межа збирача `невідомо` англійським шаблоном каже моделі «unknown», а переліки
    `СХЕМА_ПАСПОРТА` несуть член «невідомо», який звіряє розбір (`значення_схеми`), і
    ключі довідника «unknown» не знають. Значення поля зводиться до «невідомо»; елемент
    списку знімається, як `null` у `без_порожніх`: «unknown» у бажаннях — не бажання."""
    if isinstance(вузол, dict):
        return {к: невідомо_схеми(в) for к, в in вузол.items()}
    if isinstance(вузол, list):
        return [невідомо_схеми(в) for в in вузол if not _це_unknown(в)]
    return "невідомо" if _це_unknown(вузол) else вузол


def без_порожніх(вузол):
    """`null` і порожній рядок у СПИСКУ від моделі — це «нема значення», не значення.

    ── ОДНЕ МІСЦЕ, А НЕ ЛАТКА В КОЖНОМУ ЧИТАЧІ (25.09.2026, Т-19) ───────────────
      ЩО ЦЕ МІНЯЄ В РІШЕННІ. Слабка модель (MamayLM, прохід тестувальниці 25.09)
      кладе `null` у власні списки: `"бажання": [null]`, `"настрій": [null]`,
      `"питання_людині": [null]`, `"вето": {"кольори": ["темні", null]}`. Усі троє
      читачів нижче зводять елемент до тексту через `str(x)`, а `str(None)` — це
      рядок «None», і він НЕ порожній. Тому:
        · у чаті жінці стояло окреме питання «None» (`питання_людині`, рядок 1847);
        · над образами — «хочеш: None · без: none; темні · настрій: None»
          (`бажання`/`настрій`, рядок 1956; `вето`, рядок 2003);
        · а найдорожче — «none» доїжджало до `profile.жорстке_ні_фільтр`
          АБСОЛЮТНИМ фільтром і знімало 11 776 речей із 11 828 (вимір на повному
          каталозі): пул із 354 речей падав до 21, і руки не мали з чого скласти
          повний образ.
      Лікується НЕ в трьох читачах: `str(x)` над значенням, якого модель не дала,
      однаково неправильний скрізь, і четвертий читач завтра повторив би це ще раз.
      Порожнє значення знімається ОДИН раз — на вході розбору, зразу після того, як
      відповідь моделі стала об'єктом, — і далі не існує взагалі: ні в тексті для
      жінки, ні в межах пулу.
      МЕЖІ ПРАВИЛА. Чіпаються лише ЕЛЕМЕНТИ списків; значення полів словника не
      чіпаються — їх читачі вже судять самі (`об.get(k) in (None, "", [])`). Рядок
      «None», який модель написала словом, тут не ловиться і ловитись не мусить:
      це її текст, а не порожнє місце, і зникнути мовчки він права не має.
      ЦІНА НАЗВАНА. Пара з діркою коротшає: `"ошатність": [null, 7]` стає `[7]`,
      довжина вже не 2, і читач її не бере — тобто «нема значення», як і задумано,
      замість `int("None")`, який мовчки летів у `except`.
    """
    if isinstance(вузол, dict):
        return {k: без_порожніх(v) for k, v in вузол.items()}
    if isinstance(вузол, (list, tuple)):
        return [x for x in (без_порожніх(y) for y in вузол)
                if x is not None and not (isinstance(x, str) and not x.strip())]
    return вузол


