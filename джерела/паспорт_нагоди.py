def _звідки_поля(п, поле):
    """Позначка `звідки` для значення, яке ВЖЕ стоїть у паспорті під цим полем.

    Замовчування форми (11:00, +18 °C, яких вона не називала) і типова нагода речі з фото —
    це `default`, а не її слова: та сама межа, яку вже тримають `ТИПОВЕ_ПОЛЕ_ФОРМИ` і
    `ТИПОВА_НАГОДА_РЕЧІ`. Усе інше в паспорті стоїть з її вибору — рукою на плитці чи
    словом у розмові (`джерело_полів` тримає, чим саме), і це `her_words`.
    `written` поля паспорта більше не ставить: поле `письмово` прибрано (НП-в, читача не мало)."""
    факт = _КЗ.факт(п, поле)
    if факт:
        return {"her": "her_words", "hand": "her_words", "reading": "sub", "default": "default"}.get(
            факт.get("джерело"), "default")
    м = _СТ.автор((п.get("джерело_полів") or {}).get(поле))
    if м in (ТИПОВЕ_ПОЛЕ_ФОРМИ, ТИПОВА_НАГОДА_РЕЧІ):
        return "default"
    # Паспорт, який склав шов мовного шару, несе перелік полів, що шар справді повернув (`поля_шару`);
    # поле поза ним і не торкнуте рукою — типове, а не її слова
    return "default" if "поля_шару" in п and поле not in п["поля_шару"] and м not in ("her", "conversation") else "her_words"


def виміри_нагоди(паспорт=None, сценарій=None):
    """(виміри, звідки) — паспорт нагоди v2: подія вимірами кодами й сила джерела кожного.

    Виміри — єдиний вихід: словник `вимір → код` (усі оголошені виміри стоять завжди), і
    `звідки` з тими самими ключами. «Невідомо» — рядок "unknown" для виміру з переліком і
    `None` для числового; `звідки` тоді теж "unknown".

    ПОРЯДОК СИЛИ ДЖЕРЕЛ (§1.2, `ЗВІДКИ_СИЛА`): її слова → типове коду → невідомо. Пресетів
    виду більше нема (НП-в крок 2 ч.2): сходинки `preset`/`like` лишились у переліку сили, але
    нічого їх не ставить. Сильніше джерело перебиває слабше.

    Код за цими вимірами НІЧОГО НЕ РАХУЄ: це запис того, що система про подію знає, для
    журналу й звіту власника."""
    п = паспорт if isinstance(паспорт, dict) else {}
    сц = сценарій if isinstance(сценарій, dict) else {}
    виміри = {в: _ВМ_СХ.UNKNOWN for в, _, _ in ПОЛЕ_ВИМІРУ}
    виміри.update({в: None for в, _ in ЧИСЛО_ВИМІРУ})
    виміри.update(part_of_day=_ВМ_СХ.UNKNOWN, formality=None, makeup_level=_ВМ_СХ.UNKNOWN, parts=[])
    звідки = {в: _ВМ_СХ.UNKNOWN for в in виміри}

    def став(вимір, значення, джерело):
        """Ставить вимір, лише якщо джерело не слабше за те, що вже стоїть."""
        if значення in (None, "", [], _ВМ_СХ.UNKNOWN):
            return
        if ЗВІДКИ_СИЛА.index(джерело) >= ЗВІДКИ_СИЛА.index(звідки[вимір]):
            return
        if isinstance(значення, (list, tuple)):
            значення = list(значення)        # пресет — спільний на всіх; виміри — свої
        виміри[вимір], звідки[вимір] = значення, джерело

    # 1. ЇЇ СЛОВА Й ЇЇ ПЛИТКИ: те, що вже стоїть у паспорті (а поза паспортом — у сценарії).
    for вимір, поле, ключ in ПОЛЕ_ВИМІРУ:
        if not ключ:
            continue
        сире = п.get(ключ) if п.get(ключ) not in (None, "", "невідомо") else сц.get(ключ)
        # Відхилену sport-нагоду не повертає стара плитка.
        if (ключ == "нагода" and сире == "спорт" and п.get(ключ) is None
                and (п.get("джерело_полів") or {}).get(ключ) == "occasion_part_conflict"):
            continue
        if сире in (None, "", "невідомо"):
            continue
        # опади в паспорті бувають грубим «так» — канон зводить їх до слова переліку
        if ключ == "опади":
            сире = _ПОГОДА.канон_опади(сире, п.get("темп_c") or сц.get("темп_c"))
        код = _ВМ_СХ.код(поле, сире) or (str(сире) if str(сире) in _ВМ_СХ.ТАБЛИЦЯ[поле] else None)
        # намір `conventional` («нічого з цього») паспорт ставить сам, коли вона наміру не
        # назвала (`паспорт_з_json`), — це припущення коду, а не її слова (НГ-4, живий стенд:
        # «весілля гостею» давало intent=conventional (her_words)); так само `паспорт_кодами`
        # не показує його моделі як сказане
        став(вимір, код, "default" if (вимір, код) == ("intent", "conventional") else _звідки_поля(п, ключ))
    for вимір, ключ in ЧИСЛО_ВИМІРУ:
        сире = п.get(ключ) if п.get(ключ) not in (None, "") else сц.get(ключ)
        # ГОДИНА З ФОРМИ НЕ СТОЇТЬ ПОРУЧ ІЗ ЇЇ ПОРОЮ ДНЯ. Вона сказала «ввечері» —
        # `part_of_day=evening (her_words)`, — а типова година форми (11) ішла поруч як `hour=11 (default)`, і звіт
        # читався «11:00 типово» про вечірку. Типова година нічого не рахує (правила беруть `година_для_правил`),
        # тож при її порі вона лише записує протилежне: пора її слів лишається без години, поки вона не назве годину.
        джерело = "default" if вимір == "hour" and п.get(ключ) in (None, "") else _звідки_поля(п, ключ)   # година зі сценарію — типова
        if вимір == "hour" and джерело == "default" and звідки["part_of_day"] == "her_words":
            continue
        try:
            став(вимір, float(сире) if вимір != "hour" else int(float(сире)), джерело)
        except (TypeError, ValueError):
            pass
    _о = п.get("ошатність") or сц.get("ошатність")
    if isinstance(_о, (list, tuple)) and len(_о) == 2:
        став("formality", [int(_о[0]), int(_о[1])], _звідки_поля(п, "ошатність"))
    _мк = макіяж_канон(п.get("макіяж") or сц.get("макіяж")) or {}
    став("makeup_level", _ВМ_СХ.код("makeup_level", _мк.get("рівень")), _звідки_поля(п, "макіяж"))
    if виміри["hour"] is not None:
        став("part_of_day", _ПОГОДА.частина_доби(виміри["hour"] % 24), звідки["hour"])

    # 4. ТИПОВЕ КОДУ — останнім: припущення, назване припущенням.
    for ім, зн in sorted(ТИПОВЕ_ВИМІРУ.items()):
        став(ім, зн, "default")
    return виміри, звідки


