def макіяж_канон(v):
    """Макіяж одним форматом для плитки, паспорта й шва: None (не сказано / «невідомо»)
    або {«рівень»: нюд|помітний|яскравий, «губи»: «#hex»} — губи лише коли названо hex і
    рівень не нюд. Чуже слово рівня чи не-hex колір відкидаються: код не вигадує
    кольору, якого не міряв (K-IO-02). Приймає й легасі-рядок («яскравий», «#hex»)."""
    if not v:
        return None
    if isinstance(v, str):
        v = {"губи": v} if _HEX.match(v.strip()) else {"рівень": v}
    if not isinstance(v, dict):
        return None
    р = str(v.get("рівень") or "").strip().lower()
    губи = str(v.get("губи") or "").strip()
    if р not in РІВНІ_МАКІЯЖУ_ПАСПОРТА:
        if not _HEX.match(губи):
            return None
        р = "помітний"                  # названий колір без слова про рівень (як `рівень_макіяжу`)
    вих = {"рівень": р}
    if р != "нюд" and _HEX.match(губи):
        вих["губи"] = губи.lower()
    return вих


def _однакове_поле(a, b):
    """Плитка і паспорт несуть те саме значення різними типами: 19, 19.0, «19»."""
    if a in (None, "") or b in (None, ""):
        return a in (None, "") and b in (None, "")
    if isinstance(a, dict) or isinstance(b, dict):        # макіяж: {рівень, губи?} одним каноном
        return макіяж_канон(a) == макіяж_канон(b)
    try:
        return abs(float(a) - float(b)) < 1e-9
    except (TypeError, ValueError):
        return str(a).strip() == str(b).strip()


def поля_рукою(сценарій, паспорт_досі):
    """Поля-плитки, які жінка змінила РУКОЮ вже після того, як склався паспорт.

    Рішення власника «сказане нею переважає» — про СЛОВА ЖІНКИ, а не про вигадку
    моделі. Явний дотик до плитки — теж її слова, і він свіжіший за розмову, яка
    вже лягла в паспорт: доти модель, слухняна до «правда — в її словах»,
    повертала стару нагоду з розмови, і код брав її поверх щойно натиснутої
    плитки. Без паспорта досі (перший хід) дотику «після» не буває: плитка й
    слова прийшли разом, і там перші — слова."""
    сц, п = (сценарій or {}), (паспорт_досі or {})
    if not isinstance(п, dict) or not п:
        return []
    return [k for k in ПОЛЯ_ПЛИТОК
            if сц.get(k) not in (None, "") and not _однакове_поле(сц.get(k), п.get(k))]


def _ключі_довідника(група):
    """Рядок ключів для промпта: з підписом там, де він є, голим ключем — де нема."""
    return "; ".join(("%s — %s%s" % (р["ключ"], р["підпис"], (" (%s)" % р["нота"]) if р["нота"] else ""))
                     if р["плитка"] else р["ключ"] for р in довідник()[група])


def ключ_довідника(рядки, значення):
    """Значення від моделі → КЛЮЧ довідника, коли ключ уже стоїть у значенні; інакше None.

    У промпті довідник стоїть рядком `_ключі_довідника` — «ключ — Підпис (нота)», — і
    слабка модель копіює той рядок цілком: `"нагода": "робота — Робота (зустріч, …)"`
    (PR #196, знахідка 3). Звірка з голим ключем таке значення відкидала, і жінка
    діставала питання «не знаю такої нагоди», хоч відповідь лежала в самому значенні.
    Тут зводимо до ключа рівно три форми: сам ключ, сам підпис (людські слова плитки)
    і «ключ/підпис» з хвостом за роздільником (тире, двокрапка, дужка). Незнайоме
    слово («вечірка з друзями») ключем не стає й далі йде питанням: здогад сусіднім
    ключем був би тим самим мовчазним вигадуванням, що й `None`."""
    в = " ".join(str(значення or "").split()).lower()
    if not в:
        return None
    за_ключем = {р["ключ"].lower(): р["ключ"] for р in рядки}
    за_підписом = {р["підпис"].strip().lower(): р["ключ"] for р in рядки}
    початок = re.split(r"\s*[—–:(]|\s+-\s+", в, maxsplit=1)[0].strip()
    for варіант in (в, початок):
        if варіант in за_ключем:
            return за_ключем[варіант]
        if варіант in за_підписом:
            return за_підписом[варіант]
    return None


