# ЧОМУ ВІКНА ДОСИТЬ. Виклик 0 повертає ПОВНИЙ паспорт і дістає його назад наступним ходом
# (`паспорт_досі`, Т-08): суть старших ходів уже стоїть полями паспорта, а не в їхніх словах.
# Дослівно потрібне лише свіже — те, чого паспорт ще не ввібрав, і те, на що модель відповідає
# цим ходом. Старші лишаються ЗВЕДЕННЯМ (скільки їх було й останні її репліки, обрізані), щоб
# «вона це вже казала» не зникло зовсім, і зведення теж має стелю — інакше воно росло б так само.
ВІКНО_РОЗМОВИ = 10          # останніх реплік дослівно
СИМВ_РЕПЛІКИ = 600          # стеля символів на репліку вікна (окрім останньої, див. нижче)
СТАРШИХ_У_ЗВЕДЕННІ = 12     # скільки старших ЇЇ реплік лишається у зведенні
СИМВ_ЗВЕДЕННЯ = 100         # стеля символів на репліку зведення

def вікно_розмови(історія, остання_ціла=True):
    """(репліки, раніше) — розмова для промпта КОВЗНИМ ВІКНОМ (рядок 164, константи вище).

    `репліки` — останні `ВІКНО_РОЗМОВИ` реплік дослівно, рядками «She: …» / «You: …», кожна — до
    `СИМВ_РЕПЛІКИ` символів; остання — ЦІЛА, коли `остання_ціла` (у виклику 0 це її новий лист,
    сам вхід задачі). `раніше` — зведення старших {ходів, її_слова} зі стелею або None.
    СПІЛЬНЕ ДЛЯ ДВОХ ВИКЛИКІВ: виклик 0 (`промпт_паспорта`) і хід розмови мовної моделі (М-5,
    `мовний_шар.промпт_розмови`, де її нове повідомлення стоїть окремим полем, а вікно — лише те,
    що було до нього: `остання_ціла=False`). Одне вікно — одна стеля, щоб два промпти не
    розійшлися в тому, скільки розмови бачить модель."""
    усі = [х for х in (історія or []) if isinstance(х, dict) and str(х.get("текст") or "").strip()]
    вікно, старші = усі[-ВІКНО_РОЗМОВИ:], усі[:max(0, len(усі) - ВІКНО_РОЗМОВИ)]
    хто = lambda х: "You" if str(х.get("хто") or "") == "ші" else "She"

    def текст(х, стеля):
        т = str(х.get("текст") or "").strip()
        # ОСТАННЯ РЕПЛІКА ВИКЛИКУ 0 — БЕЗ СТЕЛІ: це її НОВИЙ лист, сам вхід задачі. Обрізати саме
        # його означало б втратити те, заради чого хід і робиться; стеля стоїть на попередніх.
        return т if стеля is None or len(т) <= стеля else т[:стеля].rstrip() + "…"
    репліки = ["%s: %s" % (хто(х), текст(х, None if остання_ціла and і == len(вікно) - 1 else СИМВ_РЕПЛІКИ))
               for і, х in enumerate(вікно)]
    раніше = None
    if старші:
        її = [х for х in старші if str(х.get("хто") or "") != "ші"][-СТАРШИХ_У_ЗВЕДЕННІ:]
        раніше = {"ходів": len(старші), "її_слова": [текст(х, СИМВ_ЗВЕДЕННЯ) for х in її]}
    return репліки, раніше


