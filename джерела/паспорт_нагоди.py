def _як_було(слово):
    """Заміна, що переносить велику літеру з того, що стояло в тексті: «Вам» →
    «Тобі», «вам» → «тобі». Без цього заміна на початку речення давала малу."""
    return lambda м: слово.capitalize() if м.group(0)[:1].isupper() else слово


def _жінці_про_себе(м):
    """Чоловічий рід 1-ї особи → жіночий: `-в` → `-ла`, `-ий` → `-а`, окремо
    «-шов» → «-шла» («знайшов» → «знайшла», не «знайшола») і «міг» → «могла»."""
    перед, основа, хвіст = м.group(1), м.group(2), м.group(3)
    if хвіст.lower() == "ий":
        return перед + основа + "а"
    return перед + (основа[:-2] + "шла" if основа.lower().endswith("шо") else основа + "ла")


def жінці(текст):
    """Текст моделі, що йде ЖІНЦІ: звертання на «ти», стилістка про себе — у
    жіночому роді. Заміна, не заборона: текст лишається, форма стає правильна.

    Це не косметика й не побажання — CLAUDE.md п.9: неінвазивність і форму
    забезпечує КОД, не промпт. Слова жінки (`слова`) сюди не потрапляють ніколи:
    правиться лише те, що написала модель."""
    т = str(текст or "")
    if not т.strip():
        return т
    if _ЖІНЦІ_ВИ_ВИДНО.search(т):
        for шаб, чим in _ЖІНЦІ_ЗАЙМЕННИКИ:
            т = re.sub(шаб, _як_було(чим), т, flags=re.I)
        т = _ЖІНЦІ_ВАШ.sub(
            lambda м: _як_було(_ЖІНЦІ_ТВІЙ[(м.group(1) or "").lower()])(м), т)
        т = _ЖІНЦІ_ДІЄСЛОВО.sub(
            lambda м: _як_було(_ЖІНЦІ_ДІЄСЛОВА[м.group(1).lower()])(м), т)
    т = re.sub(r"(\bя)\s+сам\b", r"\1 сама", т, flags=re.I)
    т = _ЖІНЦІ_МІГ.sub(lambda м: м.group(1) + "могла", т)
    про_себе = _ЖІНЦІ_ПРО_СЕБЕ.sub(_жінці_про_себе, т)
    if про_себе == т:
        return про_себе                     # про себе в чоловічому роді не казала
    for _ in range(3):                      # «зібрала, знайшла і взяла» — до трьох ланок
        ланка = _ЖІНЦІ_ЛАНКА.sub(_жінці_про_себе, про_себе)
        if ланка == про_себе:
            break
        про_себе = ланка
    return про_себе


