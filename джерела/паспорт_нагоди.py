# температура, опади, бажання, межі й настрій — лише словами, які мовна модель написала в хід розмови (`header` →
# `шапка` паспорта, `мовний_шар.паспорт_з_шару`); слів нема — шматка нема: число й межу жінка бачить на картці
# сценарію над шапкою. Слова прив'язані до значення поля, для якого їх написано (`для`): плитка, змінена після
# розмови, чи межа, яку код тримає не всю, знімає їх, і шапка не каже старого.
# Пора дня (`пора` паспорта) — сталі написи рядка випадку, коли години нема (п.12: написи показу, не слова коду).
ПІДПИСИ_ПОРИ = {"ранок": "Зранку", "день": "Вдень", "вечір": "Ввечері", "ніч": "Вночі"}
# Ключ `header` ходу розмови → поле паспорта, у порядку шапки (ключі — кошик А, внутрішня мова).
ШАПКА_ПОЛЯ = (("hour", "година"), ("temperature_c", "темп_c"), ("precipitation", "опади"), ("wants", "бажання"),
              ("vetoes", "вето"), ("mood", "настрій"))


def значення_шапки(п, ключ):
    """Значення поля паспорта `ключ` (`ШАПКА_ПОЛЯ`), про яке шапка говорить, — відбитком JSON; поля в шапці нема — None.

    Ті самі умови, що доти ставили шматок: замовчування форми (В-2) не стоїть фактом; опади «ні» — не опади;
    межі — лише коли код тримає ВСІ почуті: інакше слова моделі могли б назвати межу, якої код не
    тримає («без: блейзер; куртка» при її «можна куртку»)."""
    п = п if isinstance(п, dict) else {}
    if ключ in ("година", "темп_c"):
        if п.get(ключ) is None or ключ in типові_з_форми(п):
            return None
        в = [п[ключ], п.get("хвилини")] if ключ == "година" else п[ключ]
    elif ключ == "опади":
        в = п.get("опади") if п.get("опади") == "так" or _опади_словом(п) else None
    elif ключ == "вето":
        _тв, групи = вето_чинне(п), ("типи", "тканини", "принти", "кольори", "зони")
        в = sorted(str(w) for k in групи for w in (_тв.get(k) or []))
        сире = sorted(str(w) for k in групи for w in ((п.get("вето") or {}).get(k) or []))
        в = в if в and в == сире else None
    else:
        в = list(п.get(ключ) or []) or None
    return None if в is None else _json_.dumps(в, ensure_ascii=False, sort_keys=True)


def шапка_чинна(п, шапка=None):
    """Слова шапки (`{ключ: {текст, для}}`), що ще говорять про чинне значення поля; решта знімається.

    `шапка` — нові слова ходу поверх паспортних (`п["шапка"]`); без неї — лише паспортні."""
    п = п if isinstance(п, dict) else {}
    вих = {}
    for джерело in (п.get("шапка"), шапка):
        for к, з in (джерело or {}).items() if isinstance(джерело, dict) else ():
            if к in dict(ШАПКА_ПОЛЯ).values() and isinstance(з, dict) and str(з.get("текст") or "").strip() \
                    and з.get("для") is not None and з.get("для") == значення_шапки(п, к):
                вих[к] = dict(текст=str(з["текст"]).strip(), для=з["для"])
    return вих


def паспорт_шматками_людині(п):
    """Той самий випадок, що його читає ЖІНКА, — ШМАТКАМИ, кожен зі своїм КЛЮЧЕМ ПОЛЯ і `звідки` слів.

    ЩО ЦЕ МІНЯЄ В РІШЕННІ (наряд Л-9; знахідка 1 звіту
    ручного проходу). Звідси виходив ОДИН плаский
    рядок, зшитий « · », — і показ мусив ВГАДУВАТИ, що в ньому за шматок, за
    ПОЗИЦІЄЮ: `малюватиРядокВипадку` вішала піктограму-піну («тут місце») на
    шматок 0 безумовно. ПІСЛЯ: кожен шматок несе `ключ` — імʼя поля паспорта, — і
    показ бере піктограму з ключа, а слів шматка не читає (аудит/ПРОДУКТ.md п.12).

    Ключі — ті самі, що поля паспорта: `нагода` (або `подія`, коли ключа нагоди
    під її подію в довіднику нема), `місце`, `година`, `темп_c`, `опади`,
    `бажання`, `вето`, `настрій`, `пора` (лише без години, сталим написом). `код` стоїть там, де ключа мало, щоб знати,
    який саме знак: опади — це `дощ` або `сніг`, і це внутрішній код, не слово з
    екрана. `звідки` — чиї слова: `плитка` (сталий напис довідника) чи `мова`
    (мовна модель: її подія, місце словами, слова шапки ходу).

    СЛОВА (п.12): нагода — підписом довідника, місце — словами мовної моделі чи
    підписом довідника, решта — лише словами шапки, які мовна модель написала в хід розмови
    (`шапка_чинна`). Формат, тривалість, рух і дрес-код сюди НЕ їдуть: людською мовою
    вони вже стоять рядками картки сценарію, яка висить над цим самим екраном.
    """
    if not п:
        return []
    шматки = []
    def _дод(ключ, текст, звідки, код=None):
        if not текст:
            return
        шматки.append(dict(ключ=ключ, текст=str(текст), звідки=звідки, **({"код": код} if код else {})))
    нагода = слово_ключа("нагоди", п.get("нагода"))
    if нагода:
        _дод("нагода", нагода, "плитка")
    else:
        # КЛЮЧА НАГОДИ НЕМА, А ПОДІЯ Є (той самий випадок, що в `чогоБракує`): це її
        # вільне речення, і ключ у шматка інший — `подія`. Саме на ньому стояла піна.
        _дод("подія", str(п.get("подія") or "").strip()[:60], "мова")
    if str(п.get("місце_слова") or "").strip() and слово_ключа("місця", п.get("місце")):
        _дод("місце", " ".join(str(п["місце_слова"]).split()), "мова")
    else:
        _дод("місце", слово_ключа("місця", п.get("місце")), "плитка")
    шапка = шапка_чинна(п)
    for _, ключ in ШАПКА_ПОЛЯ:
        # ПОРА БЕЗ ГОДИНИ: годину в шапці несуть слова моделі до `година`; пора, названа без годинника,
        # слів шапки не має, і над картками про час не було нічого. Шматок пори — сталим написом, коли години нема
        if ключ == "година" and ключ not in шапка and п.get("година") is None and п.get("пора") in ПІДПИСИ_ПОРИ:
            _дод("пора", ПІДПИСИ_ПОРИ[п["пора"]], "плитка", п["пора"])
        if ключ in шапка:
            # знак опадів — код поля (`так` — сніг на морозі, дощ решту), а не слово
            код = None if ключ != "опади" else (п["опади"] if п["опади"] != "так" else (
                "сніг" if п.get("темп_c") is not None and float(п["темп_c"]) <= 0 else "дощ"))
            _дод(ключ, шапка[ключ]["текст"], "мова", код)
    return шматки


def паспорт_рядком_людині(п):
    """Той самий випадок — але словами, якими його читає ЖІНКА, а не модель.

    ЩО ЦЕ МІНЯЄ (ручний огляд куратора). Над
    картками стояв `паспорт_рядком` — рядок, писаний ДЛЯ МОДЕЛІ: «робочий день в
    офісі, робота, офіс корпоративний, приміщення, близько 9 год, сидіти,
    дрес-код business_casual, 09:00, 18 °C». Жінка, яка прийшла не через чат, на
    тому самому місці бачить «Робота · офіс · 09:00 · 18 °C» — і це та сама
    сторінка, той самий рядок і той самий випадок. Рядок для моделі лишається
    незмінним: його читають руки 3–4, і він мусить нести ключі, а не підписи.

    СКЛАД РЯДКА ЖИВЕ В `паспорт_шматками_людині` (наряд Л-9): тут — рівно ті самі
    шматки, зшиті « · ». Рядок потрібен там, де читач — не піктограма, а текст:
    назва сценарію в бібліотеці, журнал, старі записи. Показ бере шматки з
    ключами, щоб не вгадувати знак за позицією.
    """
    return " · ".join(ш["текст"] for ш in паспорт_шматками_людині(п))
