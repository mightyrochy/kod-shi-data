def ключ_довідника(рядки, значення):
    """Значення від моделі → КЛЮЧ довідника, коли ключ уже стоїть у значенні; інакше None.

    У промпті довідник стоїть рядком `_ключі_довідника` — «ключ — Підпис (нота)», — і
    слабка модель копіює той рядок цілком: `"нагода": "робота — Робота (зустріч, …)"`
    (PR #196, знахідка 3). Звірка з голим ключем таке значення відкидала, і жінка
    діставала питання «не знаю такої нагоди», хоч відповідь лежала в самому значенні.
    Тут зводимо до ключа рівно три форми: сам ключ, сам підпис (людські слова плитки)
    і «ключ/підпис» з хвостом за роздільником (тире, двокрапка, дужка). Незнайоме
    слово («вечірка з друзями») ключем не стає й іде рядком у звіт власника: здогад сусіднім
    ключем був би тим самим мовчазним вигадуванням, що й `None`."""
    в = " ".join(str(значення or "").split()).lower()
    if not в:
        return None
    за_ключем = {р["ключ"].lower(): р["ключ"] for р in рядки}
    за_підписом = {р["підпис"].strip().lower(): р["ключ"] for р in рядки}
    початок = re.split(r"\s*[—–:(]|\s+-\s+", в, maxsplit=1)[0].strip()
    for варіант in (в, початок):
        if варіант in за_ключем:
            return за_ключем[варіант]
        if варіант in за_підписом:
            return за_підписом[варіант]
    return None


