    _дані = list((_досі_п.get("поради_дані") or [])) if isinstance(_досі_п.get("поради_дані"), list) else []
    if _дані:
        п["поради_дані"] = list(_дані)
    п["порада_людині"] = ""
    # РЕЧІ З ФОТО — у паспорті в обох гілках (рядок 152): спершу ті, що вже є, плюс
    # порожні місця під нові фото; відповідь моделі нижче лише доповнює їх описом.
    import річ_з_фото as _РФ
    # її річ словами, без фото (рядок 157): клаузи зі станом «певна / непевна / відмова»;
    # «відмова» сама річ не будить, але знімає її ж річ словами, що вже лежала
    _словами = list(словами or [])
    _є_річ = bool(фото or _досі_п.get("речі_з_фото") or [д for д in _словами if д["стан"] != "відмова"])
    if _є_річ:
        п["речі_з_фото"] = _РФ.речі_з_json([], фото, досі=_досі_п.get("речі_з_фото"),
                                           словами=_словами)
    _речі_звіт(п, _словами)
    т = str(текст or "").strip()
    об = None
    # ЧОМУ САМЕ НЕ РОЗІБРАЛОСЬ — ОКРЕМИМ ПОЛЕМ, А НЕ ЛИШЕ ФАКТОМ ПРОВАЛУ: показ
    # вкладає цей рядок у другу спробу (Н-V07-022), інакше повторний виклик просить
    # те саме тими самими словами, які вже не спрацювали.
    помилка = "порожня відповідь"
    if т:
        м = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", т, re.S)
        сир = м.group(1) if м else т[т.find("{"):т.rfind("}") + 1]
        # П.14 (СТАНДАРТ §4): вхід тут — СИРИЙ ТЕКСТ МОДЕЛІ, і «це не JSON» —
        # його нормальний стан, а не поломка коду; споживач бачить його полем
        # `помилка_формату`, яке показ друкує жінці (`показ.html:4962`). Тому
        # тип вузький і названий: `json.JSONDecodeError` — підклас ValueError,
        # TypeError — коли зрізу взагалі не вийшло рядка. Решта летить далі.
        try:
            об = _json_.loads(сир)
            помилка = None if isinstance(об, dict) else ("JSON, але не об'єкт (%s)"
                                                         % type(об).__name__)
        except (ValueError, TypeError) as e:
            об, помилка = None, "не JSON (%s)" % str(e)[:60]
    if not isinstance(об, dict):
        п["помилка_формату"] = помилка
        # ЧИННІ МЕЖІ РАХУЮТЬСЯ ОСТАННІМИ, В ОБОХ ГІЛКАХ (рядок 156): `вето` до
        # цього рядка ще зливається з відповіддю моделі, і порахувати їх раніше
        # означало б віддати показу й шву список, якого вже нема.
        п["вето_тверде"] = вето_тверде(п)
        # типова нагода — лише коли речі справді лежать (рядок 157: «відмова» речей не лишає)
        if п.get("речі_з_фото"):
            _типова_нагода(п)
        # ВИМІРИ — ОСТАННІМИ, В ОБОХ ГІЛКАХ (НГ-1): вище ще ставиться нагода (типова нагода
        # речі з фото), а виміри виводяться з неї. Код за ними нічого не рахує — НГ-2.
        п["виміри"], п["звідки"] = виміри_нагоди(п, сц)
        return п
    п["джерело"] = "модель"
    # ── ПОРОЖНЄ МІСЦЕ ВІД МОДЕЛІ ЗНІМАЄТЬСЯ ТУТ, І БІЛЬШЕ НІДЕ (Т-19, 25.09) ──
    # Єдиний вхід усієї відповіді: нижче вона вже не існує ніде інде, тож
    # `null` і порожній рядок у будь-якому її списку далі не їдуть ні в текст
    # для жінки, ні в межі пулу. Чому саме тут, а не в трьох читачах —
    # докстрінг `без_порожніх`.
    об = невідомо_схеми(без_порожніх(об))
    # ── ПОЛЕ, НАЗВАНЕ МОДЕЛЛЮ В «НЕВІДОМО», НЕ ЧИТАЄТЬСЯ ВЗАГАЛІ (PR #196) ─────
    # Те саме правило, що вже стояло для макіяжу («„невідомо“ від моделі не затирає
    # плитку»), тільки не для одного поля, а для всіх: відповідь викидається ДО
    # читання, тож лишається те, що було б і без моделі — дефолт сценарію, плитка,
    # `паспорт_досі`, слова, які код упізнав сам. Список `невідомо` їде далі як є.
    _названі_невідомими = поля_названі_невідомими(об)
    if _названі_невідомими:
        об = {k: v for k, v in об.items() if k not in _названі_невідомими}
    for k in ("подія", "формат", "рух", "дрес_код", "опади"):
        if об.get(k) in (None, "", []):
            continue
        # ПЕРЕЛІК ІЗ ПРОМПТА НЕ Є ВІДПОВІДДЮ (В-11): «сидіти | ходити» — це варіанти
        # схеми, а не її день. Правило й вимір — у `значення_схеми`.
        _члени, _член = перелік_схеми(k), значення_схеми(k, об[k])
        if _члени and _член is None:
            п.setdefault("не_взято_кодом", []).append(
                "not_taken · step=call0 · field=%s · model_said=%s · reason=not_in_schema · allowed=%s · kept=%s"
                % (k, _json_.dumps(" ".join(str(об[k]).split())[:80], ensure_ascii=False), "|".join(_члени),
                   _json_.dumps(п.get(k), ensure_ascii=False)))
            continue
        # ФОРМАТ ВІД МОДЕЛІ ВИКЛИКУ 0 — «НЕВІДОМО» (Ч-4): «просто неба» бере зовнішній шар у
        # пулі, а опору в її словах доти шукала регулярка коду; тепер це робить лише шар
        if k == "формат" and not шар and str(об[k]).strip() != "невідомо":
            п.setdefault("не_взято_кодом", []).append(
                "not_taken · step=call0 · field=формат · model_said=%s · reason=no_language_layer · kept=unknown"
                % _json_.dumps(str(об[k]).strip(), ensure_ascii=False))
            continue
        п[k] = _член or str(об[k]).strip()
    # ── НАГОДА Й МІСЦЕ — КЛЮЧАМИ ДОВІДНИКА (Т-08 крок 1) ──────────────────────
    # Це ті самі ключі, з яких малюються плитки: відомий ключ переважає плитку
    # (слова людини — перші), невідомий не підставляється сусіднім словом і не
    # гине мовчки — плитка лишається як була, а слово моделі йде рядком у звіт
    # власника. ПИТАННЯ СЛОВАМИ КОДУ ЇЙ НЕМА (Ч-4, кошик В): доти код сам писав їй
    # ««…» — не знаю такої нагоди; обери з плиток або опиши інакше»; речення для неї
    # пише лише мовна модель, а плитка з порожнім значенням уже каже, чого бракує.
    _дов = довідник()
    for k, група in (("нагода", "нагоди"), ("місце", "місця")):
        v = об.get(k)
        if v in (None, "", "невідомо"):
            continue
        v = str(v).strip()
        ключ = ключ_довідника(_дов[група], v)
        # ── МІСЦЕ ВІД МОДЕЛІ ВИКЛИКУ 0 — «НЕВІДОМО» (Ч-4) ──────────────────────
        # Доти ключ тримала опора в її словах (слова довідника, рядок 209) і «коротка
        # поїздка» проти «дороги» (рядок 188) — регулярки коду. Місце з її слів дає лише
        # шар (`place` на уривку); без нього плитка лишається як була.
        if k == "місце" and ключ and not шар:
            п.setdefault("не_взято_кодом", []).append(
                "not_taken · step=call0 · field=місце · model_said=%s · reason=no_language_layer · kept=%s"
                % (_json_.dumps(ключ, ensure_ascii=False),
                   _json_.dumps(сц.get("місце"), ensure_ascii=False) if сц.get("місце") not in (None, "") else "unknown"))
            continue
        if ключ:
            п[k] = ключ
        else:
            п.setdefault("не_взято_кодом", []).append(
                "not_taken · step=call0 · field=%s · model_said=%s · reason=not_in_dictionary · kept=tile"
                % (k, _json_.dumps(v[:80], ensure_ascii=False)))
    # ── ПОЛЯ РОЗМОВИ: питання моделі до жінки й одне речення для неї ───────────
    # ЗВЕРТАННЯ Й РІД — КОДОМ, НЕ ПРОМПТОМ (З-4, З-5в): усе, що модель написала
    # ЖІНЦІ, проходить `жінці()`. Її власні слова (`слова`) не чіпаються.
    if isinstance(об.get("питання_людині"), list):
        п["питання_людині"] = [жінці(str(x).strip()[:200]) for x in об["питання_людині"]
                               if str(x).strip()][:ПИТАНЬ_ЛЮДИНІ_МАКС]
    if str(об.get("відповідь_людині") or "").strip():
        п["відповідь_людині"] = жінці(str(об["відповідь_людині"]).strip()[:400])
    else:
        # ── ВІДПОВІДЬ СТИЛІСТКИ НЕ ГУБИТЬСЯ МОВЧКИ (В-12, розбір 1/8) ─────────
        # ЩО ВИДНО (звіт ноутбука 25.09, жива gemma-4-12b): модель повернула ключ
        # «відповідь_людини» замість «відповідь_людині». Розбір читав лише точне
        # ім'я, поля не було — і в чаті лишився сам рядок коду про річ, без жодного
        # слова стилістки. Жінка бачила, що її спитали, і не бачила відповіді.
        # СЛОВНИКА ОДРУКІВОК ТУТ НЕМА І НЕ БУДЕ (п.12): вгадувати, який саме ключ
        # модель зіпсувала, означало б множити список щоразу, як вона зіпсує його
        # інакше. Правило безіменне: коли поля відповіді нема, а в об'єкті є РІВНО
        # ОДИН чужий ключ із текстом — це вона й є. Кілька чужих текстів або жодного
        # — код не вгадує: ставить `потрібен_повтор`, і показ перепитує ОДИН раз,
        # називаючи потрібне поле. В обох випадках рядок іде у звіт власника — ніщо
        # не зникає тихо (п.14).
        # `чекати_відповідь` — чи ЦЕЙ виклик просив у моделі речення для жінки. Виклик 0
        # просить (поле є у схемі), переклад внутрішньої мови — ні: там репліку складає
        # код, і повтор був би викликом ні за що.
        _знані = set(СХЕМА_ПАСПОРТА) | set(ПОЛЯ_ПОЗА_СХЕМОЮ_ПАСПОРТА)
        _чужі_тексти = [(k, " ".join(str(v).split())) for k, v in об.items()
                        if k not in _знані and isinstance(v, str)
                        and len(" ".join(str(v).split())) >= ВІДПОВІДЬ_ЧУЖИМ_КЛЮЧЕМ_МІН]
        if len(_чужі_тексти) == 1:
            _к, _текст = _чужі_тексти[0]
            п["відповідь_людині"] = жінці(_текст[:400])
            п.setdefault("не_взято_кодом", []).append(
                "answer_under_other_key · step=call0 · key=%s · code=taken · outfits_changed=no"
                % _json_.dumps(_к, ensure_ascii=False))
        elif чекати_відповідь:
            п["потрібен_повтор"] = ("у відповіді нема поля «відповідь_людині»"
                                    + (", а чужих текстів %d — котрий із них відповідь, код не "
                                       "вгадує" % len(_чужі_тексти) if _чужі_тексти
                                       else " і жодного іншого тексту"))
