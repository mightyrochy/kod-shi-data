def довідник():
    """Нагоди, місця й дрес-коди — РІВНО ті ключі, з яких рахує `формальність.сценарій`,
    з межами звідти ж і словами для людини з `ДОВІДНИК_ПІДПИСИ`.

    Порядок — за серединою діапазону (від дому до white tie), щоб плитки й
    списки йшли шкалою ошатності, а не абеткою. `дефолт_діапазон` — той самий
    «широкий дефолт» невідомого середовища, що стоїть в `формальність.сценарій`."""
    import outfit as _O
    import колір_образу as _КОЛІР, реєстр_правил as _РЕЄСТР, формальність as _ФОРМ   # Н-02-01, сесія 4

    def _ряд(група, ключ, діап, **решта):
        """Один рядок довідника: ключ, слова для людини й межі ошатності.

        `плитка` = «цей ключ названо в `ДОВІДНИК_ПІДПИСИ`»: плиткою на екрані
        стає лише те, для чого є людські слова, а решта лишається в списку з
        ключем, підставленим замість підпису, — не зникає."""
        підпис, нота = ДОВІДНИК_ПІДПИСИ[група].get(ключ, (ключ.replace("_", " "), ""))
        return dict(ключ=ключ, підпис=підпис, нота=нота, діапазон=list(діап),
                    плитка=(ключ in ДОВІДНИК_ПІДПИСИ[група]), **решта)
    _шкалою = lambda р: (sum(р["діапазон"]) / 2.0, р["діапазон"][0], р["ключ"])
    таблиці = dict(
        нагоди=sorted((_ряд("нагоди", к, _ФОРМ.МІСЦЯ_ДІАПАЗОНИ[м], місце=м)
                       for к, м in _ФОРМ.НАГОДА_У_МІСЦЕ.items() if м in _ФОРМ.МІСЦЯ_ДІАПАЗОНИ),
                      key=_шкалою),
        місця=sorted((_ряд("місця", к, v) for к, v in _ФОРМ.МІСЦЯ_ДІАПАЗОНИ.items()), key=_шкалою),
        коди=sorted((_ряд("коди", к, v) for к, v in _ФОРМ.КОДИ_ДІАПАЗОНИ.items()), key=_шкалою))
    for група, рядки in таблиці.items():
        зайві = sorted(set(ДОВІДНИК_ПІДПИСИ[група]) - {р["ключ"] for р in рядки})
        if зайві:
            raise ValueError("довідник: підпис без ключа в коді — %s %s" % (група, зайві))
    return dict(таблиці, дефолт_діапазон=[3, 6], шкала="1 домашнє … 10 white tie")


