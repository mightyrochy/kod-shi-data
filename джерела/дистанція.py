    """Базова приобличчева вага слота + дистанція → вага, на якій судять цей образ.

    `дистанція=None` (або незнайома) повертає БАЗУ без змін — це і є «поведінка як
    сьогодні». Лінійна інтерполяція, а не крива: корпус дає напрям і не дає форми."""
    б = float(база or 0.0)
    if дистанція not in ДИСТАНЦІЇ:
        return б
    я = ЯКОРІ[зона(б)][дистанція]
    return max(0.0, min(1.0, round(б + ЧАСТКА * (я - б), 3)))


