def _канон(v):
    return (str(v or "")).strip().lower().replace(" ", "_")


def _з_місця(місце):
    """Місце → (дистанція, чому). Порядок той самий, що у `формальність.сценарій`:
    точний ключ, далі однозначний префікс. Неоднозначний префікс приймається лише
    тоді, коли ВСІ збіги кажуть одне («офіс» → корпоративний і креативний, обидва
    розмова); щойно вони розходяться — мовчимо."""
    м = _канон(місце)
    if not м:
        return None, None
    if м in МОВЧАТЬ:
        return None, "місце «%s»: %s" % (м, МОВЧАТЬ[м])
    if м in МІСЦЕ:
        д, чому = МІСЦЕ[м]
        return д, "місце «%s» — %s" % (м, чому)
    зб = [k for k in МІСЦЕ if k.startswith(м) or м in k]
    if зб and len({МІСЦЕ[k][0] for k in зб}) == 1:
        д, чому = МІСЦЕ[зб[0]]
        return д, "місце «%s» → %s — %s" % (м, "|".join(sorted(зб)), чому)
    if зб:
        return None, ("місце «%s» неоднозначне (%s) і збіги кажуть різне — "
                      "дистанція не виводиться" % (м, "|".join(sorted(зб))))
    return None, "місце «%s» таблиці невідоме" % м


def з_сценарію(с):
    """Сценарій нагоди → dict(дистанція, чому, джерело, поля).

    `дистанція` — один із `ДИСТАНЦІЇ` або None. None означає «не знаю», і всі
    троє споживачів на ньому поводяться рівно як до появи цієї осі.

    Порядок входів — той самий, що вже стоїть у `формальність.сценарій`, і з тієї
    самої причини: практики одностайні, що МІСЦЕ важить більше за назву події.
      1. місце (точний ключ, далі однозначний префікс);
      2. нагода — спершу власним рядком, далі через `формальність.НАГОДА_У_МІСЦЕ`
         (одне зшиття нагоди з місцем на всю систему, не друге);
      3. формат — лише «просто неба», і лише коли перші два змовчали.
    """
    с = dict(с or {})
    поля = {k: с.get(k) for k in ПОЛЯ_ВХОДУ}
    д, чому = _з_місця(с.get("місце"))
    if д:
        return dict(дистанція=д, чому=чому, джерело="місце", поля=поля)
    н = _канон(с.get("нагода"))
    if н in НАГОДА:
        дн, чому_н = НАГОДА[н]
        return dict(дистанція=дн, чому="нагода «%s» — %s" % (н, чому_н),
                    джерело="нагода", поля=поля)
    if н:
        try:
            import формальність as _Ф
            в_місце = _Ф.НАГОДА_У_МІСЦЕ.get(н)
        except Exception:
            в_місце = None
        if в_місце:
            дн, чому_н = _з_місця(в_місце)
            if дн:
                return dict(дистанція=дн, джерело="нагода→місце",
                            чому="нагода «%s» → %s" % (н, чому_н), поля=поля)
    ф = (str(с.get("формат") or "")).strip().lower()
    if ф in ФОРМАТ:
        дф, чому_ф = ФОРМАТ[ф]
        return dict(дистанція=дф, чому="формат «%s» — %s" % (ф, чому_ф),
                    джерело="формат", поля=поля)
    бракує = [k for k in ПОЛЯ_ВХОДУ if not с.get(k)]
    хвіст = ФОРМАТ_МОВЧИТЬ.get(ф)
    причина = чому or ("порожні поля: " + ", ".join(бракує) if бракує else
                       "жодне з полів не веде в таблицю")
    if хвіст:
        причина += "; формат «%s»: %s" % (ф, хвіст)
    return dict(дистанція=None, чому=причина, джерело=None, поля=поля)


def зона(база):
    """Зона слота за його БАЗОВОЮ приобличчевою вагою (див. ЗОНА_* вище)."""
    б = float(база or 0.0)
    if б >= ЗОНА_ПРИОБЛИЧЧЯ:
        return "приобличчя"
    if б <= ЗОНА_ВІД_ОБЛИЧЧЯ:
        return "від_обличчя"
    return "корпус"


