# ЩО БУЛО (рядки 243, 400; перевірка #481, стенд сід 3): НГ-2 розвів рішення коду (18 різних
# на 18 нагод), а пул руки 1 лишався тим самим. Униз смуги тут діяв допуск корпусу K-KOH-02 (2
# кроки, взуттю 1): футболка 2–4 і шопер 2–3 проходили на «офіційний захід удень» 5–7 і в офіс
# 4–6, кеди й уги 2–4 — у театр. А тип, якого шар не знає (73 % сумок — «сумка_без_уточнення»,
# 84 % головних уборів без типу: берет, панама), проходив МОВЧКИ, хоч бал фото в нього є (462 з 477).
# Пропуск у межах розкиду — право ОБРАЗУ (K-KOH-02: високе з низьким), а не речі: річ, нижча за
# саму нагоду, у когерентний образ для неї не стає, і модель брала її першою-ліпшою.
# ЩО ТЕПЕР (ЛИШЕ ВНИЗ; угору допуск той самий, що доти — див. нижче). Свідків два, обидва вже є:
#   • інтервал речі `формальність.інтервал_формальності` (тип ∩ модифікатор + полярності тканини —
#     те саме «форм. a–b», що стоїть у рядку пулу моделі); стеля нижче смуги → `item_below_band`;
#   • стеля РІВНО на нижньому краї смуги — річ влазить лише найошатнішою версією свого типу; тут
#     вирішує бал фото: нижче смуги → `item_at_band_floor_photo_below` (обидва свідки кажуть «нижче»);
#   • тип невідомий, бал фото є → бал читається як ±1 (згода фото з типом ±1 — 75.3 %, рядок 150):
#     бал ≤ lo − 2 → `untyped_photo_below_band`;
#   • ні типу, ні бала — річ лишається (незнання не вирок), а в ранзі пулу стоїть позаду речі,
#     чий бал у смузі (`композитор_слоти._ранг_фото`).
# ОЧИМА (аркуші фото, 01.10, каталог_повний, по 12 випадкових): дотик + фото нижче, театр 4–6 — 12 з
# 12 доречно зняти (шльопанці, рвані джинси, базові футболки, трикотажні шорти); нижче смуги на
# офіційному заході 5–7 — 11 з 12 (футболки, худі, шорти, кросівки, спортивні штани; спірне — поло
# гладкої в'язки); дотик + фото 4 в офісі 6–8 — 8 з 12 (сабо, бохо-блуза, кардиган з капюшоном,
# боді, плетені речі; спірні — гладкі джемпери, але смуга 6–8 — це ділова нагода, не business
# casual); сумки без типу з балом 4 — пляжна плетінка, сітка, нейлоновий «банан», гобеленова
