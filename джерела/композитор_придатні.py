# ── ФОРМАЛЬНІСТЬ ТИПУ ПОЗА СЦЕНОЮ — ВІДСІВ ДО ПУЛУ (04.09.2026) ────────────
# ЩО ЦЕ МІНЯЄ (правило 3, вимір на каталог_повний, побачення · ресторан_районний
# 4–5 · 18 °C): у пулі 972 речі, з них 67 мають тип, чия формальність лежить поза
# сценою далі, ніж будь-який допуск корпусу: 30 костюмів (8), 21 рюкзак (2),
# 6 поясних, 4 клатчі, 3 домашні, 3 вечірні сукні. Доти їх бачила модель, а
# K-KOH-02 казав «розкид більший за два кроки» ПІСЛЯ вибору. Судити за ознакою,
# яку можна було відсіяти до подачі, — марна робота моделі й марний рядок судді.
# СИЛА ≤ ВЕРИФІКАЦІЯ: межа — не нова константа, а найширший допуск корпусу
# (форм_розкид_макс, K-KOH-02, T3) плюс один крок на «red sneakers» (K-KOH-03):
# річ, яка НЕ здатна стати в межі навіть з обома поблажками, не може бути в
# когерентному образі для цієї сцени. Тип невідомий → річ лишається: невідоме
# не відсіюється (377 речей без типу на тому самому пулі).
def смуга_нагоди(сцен):
    """(lo, hi) ошатності НАГОДИ за шкалою 1–10, або None, коли сцени нема.

    ОДИН СВІДОК НА ДВОХ ЧИТАЧІВ (21.09.2026, рядок 119). Смугу рахував лише
    `_поза_сценою` — і вона вмирала всередині нього разом із допуском корпусу.
    Відколи пул ВЕРХНЬОГО ШАРУ судиться тією самою смугою
    (`композитор_слоти._за_ошатністю_нагоди`), два місця мусять брати її з
    одного розрахунку: інакше добір слота й відсів зі сцени розійшлись би на
    першій же зміні таблиці, і ніхто б цього не побачив.

    Джерело те саме, що доти: таблиця `формальність.сценарій` (місце + код +
    година), яку ПЕРЕВАЖУЄ `_ошатність` із паспорта випадку — слова людини перші."""
    # П.14 (СТАНДАРТ §4): «нічого не чіпаємо» має рівно одну законну причину —
    # сцени нема, і вона названа всередині `смуга_ошатності`. Друга, невідрізненна,
    # була поломкою `формальність.сценарій`: пул мовчки лишався з речами поза
    # сценою, а смуга формальності в діагностиці стояла порожня, наче її не питали.
    # ОДИН РОЗРАХУНОК НА ВСІХ (розбір 3/8, вада 2): дрес-код сюди не доїжджав —
    # докстрінг обіцяв «місце + код + година», а код `код` не подавав, і смуга
    # тут розходилась із тією, якою судили її річ із фото. Порядок джерел той
    # самий: штамп прогону → слова людини → таблиця.
    смуга = _ФОРМ.смуга_ошатності(сцен)
    return (смуга[0], смуга[1]) if смуга else None


def смуга_рангу(сцен):
    """(lo, hi) смуги РАНГУ нагоди, коли числа ошатності нема, а код нагоди — ключ `МІСЦЯ_ДІАПАЗОНИ`.

    Лише порядок у черзі семплера (`композитор_слоти._ранг_нагоди`), не фільтр і не `смуга_нагоди`: пул
    нічого не втрачає, суд нічого не отримує (п.17). Названа смуга — число мовної моделі — переважує: тоді None.
    Нагода не з таблиці (робота, побачення, свято…) — None, ранг не діє. Ключ — код, слів код не читає (п.12)."""
    if смуга_нагоди(сцен) is not None:
        return None
    д = _ФОРМ.МІСЦЯ_ДІАПАЗОНИ.get(str((сцен or {}).get("нагода") or "").strip().lower().replace(" ", "_"))
    return (float(д[0]), float(д[1])) if д else None


# ── КАЗУАЛЬНІШЕ ЗА СМУГУ — МІРИЛО НГ-2б (01.10.2026); З ВІДСІВ-1 (02.10) — ПОЗНАЧКА, НЕ ВЕТО ──
# ВІДСІВ-1 (рішення власника 02.10: «Відсів має бути на рівні суду. Якщо модель взяла недоречну
# річ і не написала пояснення, чому саме її, значить, можливо, вона помилилася»). Мірило нижче
# лишається тим самим, але пул більше НЕ знімає речей нижче смуги: кожна стоїть у пулі з
# позначкою `_нижче_смуги` (код причини), модель бачить її полем «below_band», а суд
# (`суд_від_моделі.нижче_смуги_образу`, K-KOH-07) ставить знахідку, коли річ в образі є, а
# пояснення саме цієї речі в «deliberate» нема. Історія НГ-2б нижче — чому мірило таке.
# Річ нижче нагоди залишається з позначкою для суду. Обидва напрямки порівняння
# беруть `інтервал_формальності`: таблиця типу й сирий бал фото не є паралельними
# шкалами. Невідомий інтервал не відсіюється й не отримує позначки.


def нижче_смуги(r, lo):
    """Код зауваження, коли канонічна смуга речі цілком нижча за нагоду.

    Пул, суд і поломка руки 2 читають один інтервал; другого голосу сирого
    фото-бала чи окремого винятку для точкових типів тут немає.
    """
    _, стеля = _ФОРМ.інтервал_формальності(r)
    return "item_below_band" if стеля is not None and стеля < lo else None


def _поза_сценою(речі, сцен):
    """(лишились, геть, діапазон) — геть ідуть речі, ошатніші за смугу далі, ніж допуск корпусу.
    Без сцени — нічого не чіпає.

    КАЗУАЛЬНІШЕ ЗА СМУГУ — У ПУЛІ З ПОЗНАЧКОЮ (ВІДСІВ-1, 02.10.2026). Річ, яку `нижче_смуги`
    міряє нижчою за нагоду, лишається, і її копія несе `_нижче_смуги` (код причини; самі
    записи каталогу не міняються). Судить це суд (`суд_від_моделі.нижче_смуги_образу`):
    модель, що взяла таку річ без пояснення в «deliberate», дістає знахідку K-KOH-07."""
    сцен = dict(сцен or {})
    _смуга = смуга_нагоди(сцен)
    if _смуга is None:
        return речі, [], None
    # СМУГА ПРОГОНУ — ПАРАМЕТР K-KOH-02 (`поломки`): у руці 2 — сусідній щабель за краєм смуги нагоди, і пул
    # лишає лише речі цього щабля. Вужчі допуски — свої правила (рядок 555) і стоять від справної смуги:
    # взуття — K-SHO-03 (на щабель від рівня образу), рівень ≥ 7 — K-KOH-08 (не перевершити господиню),
    # намір — K-PER-00; річ іде геть, коли її ріже хоч одне.
    import collections as _кол
    import поломки as _ПОЛ
    _ПОЛ.свідок("K-KOH-02", "pool", смуга=list(_смуга))
    lo, hi = _смуга
    _смуга_прогону = _ПОЛ.злам("K-KOH-02", "смуга", _смуга)
    _поза_щаблем = _ПОЛ.злам("K-KOH-02", "пул", frozenset(), речі=речі, смуга=_смуга, ціль=_смуга_прогону)
    # ДОПУСК = РОЗКИД КОРПУСУ (K-KOH-02, 2 кроки) БЕЗ «+1 на red sneakers»: свідомий розрив —
    # право моделі через СВІДОМО/«потрібно», не дефолт пулу. Виміряно 05.09: із +1 на весілля
    # (7–9) і в офіс business formal у пул ішли кросівки 33–35 і кеди 21–22.
    доп = float(_РЕЄСТР.C.get("форм_розкид_макс", 2))
    # ДОРЕЧНІСТЬ ЯК НАМІР (K-PER-00 context_optimal): «maximise appropriateness» — допуск смуги звужується
    # до одного щабля для ВСІХ слотів, не лише для взуття й рівня ≥ 7. Ключ константи — у лексиконі наміру.
    _допуск_наміру = _РЕЄСТР._намір(сцен.get("intent"), сцен.get("мета_важливо"))["форм_допуск"]
    _спільні = [("K-KOH-02", доп)] + ([("K-PER-00", float(_РЕЄСТР.C[_допуск_наміру]))] if _допуск_наміру else []) \
        + ([("K-KOH-08", 1.0)] if lo >= 7 else [])
    лиш, геть, тінь = [], [], _кол.Counter()
    for r in речі:
        if id(r) in _поза_щаблем:
            геть.append(r); continue
        _нижче = нижче_смуги(r, _смуга_прогону[0])
        if _нижче:
            # нижча за нагоду річ доступна стилістці з позначкою, а рішення — за судом (K-KOH-07)
            лиш.append(dict(r, _нижче_смуги=_нижче)); continue
        l, h = _ФОРМ.інтервал_формальності(r)
        if l is None:
            лиш.append(r); continue
        ріжуть = [к for к, д in _спільні + ([("K-SHO-03", 1.0)] if r.get("слот") == "взуття" else [])
                  if l > (_смуга_прогону[1] if к == "K-KOH-02" else hi) + д]
        тінь.update(к for к in ріжуть if к != "K-KOH-02")
        (геть if ріжуть else лиш).append(r)
    for к, n in sorted(тінь.items()):
        _ПОЛ.свідок(к, "pool", смуга=list(_смуга), скільки=n)
    return лиш, геть, (lo, hi)


def _придатні(каталог, жорстке_ні, вето, тіло, сцен=None):
    """Абсолютні фільтри ДО будь-якого впорядкування. Порядок значущий: спершу те,
    що людина заборонила (жодних торгів), потім сцена. Наявність на сайті (`available`) річ із пулу
    не виключає (слово власника 16.10.2026, п.16): збірка тестова, поле лишається даними запису."""
    відкинуто = []
    речі, _геть, _д = _поза_сценою(list(каталог), сцен)
    if _геть:
        # НГ-2б: причина — КОД (п.12), і зняте розкладене за кодами `нижче_смуги` / `item_above_band`;
        # тип може бути None (річ без типу знято за балом фото), тож сорт — рядком.
        import collections as _кол
        відкинуто.append(dict(причина="item_formality_off_band", смуга=_д,
                              скільки=len(_геть),
                              за_причиною=dict(_кол.Counter(нижче_смуги(r, _д[0]) or "item_above_band"
                                                             for r in _геть)),
                              типи=sorted({str(r.get("тип")) for r in _геть}),
                              приклади=[x["назва"][:40] for x in _геть[:3]]))
    # ТИПИ, ЗАБОРОНЕНІ ЗАЯВЛЕНИМ ДРЕС-КОДОМ, У ПУЛ НЕ ЙДУТЬ (16.09.2026, K-KOH-05).
    # Доти смуга формальності з допуском +1 пускала футболку й джинси в офіс під
    # business_casual, а суддя потім лише зауважував. Заборона корпусу категорійна
    # («no denim in conservative environments»), тож діє до моделі, а не після.
    # П.14: `_код = None` на поломку означало б «дрес-коду не заявлено» — тобто
    # тиху відміну категоричної заборони корпусу (K-KOH-05) рівно там, де жінка
    # дрес-код ЗАЯВИЛА. `код_дрес` віддає None на незнане слово сам.
    _код = _ФОРМ.код_дрес((сцен or {}).get("дрес_код")) if (сцен or {}).get("дрес_код") else None
    _забор = set(_ФОРМ.КОДИ_ТИП_ЗАБОРОНА.get(_код) or ()) if _код else set()
    if _код == "casual":
        _забор |= _ФОРМ.типи_нижче_межі(2)
    if _забор:
        _геть_код = [r for r in речі if r.get("тип") in _забор]
        if _геть_код:
            речі = [r for r in речі if r.get("тип") not in _забор]
            відкинуто.append(dict(причина="тип заборонений дрес-кодом «%s» (K-KOH-05)" % _код,
                                  скільки=len(_геть_код),
                                  типи=sorted({r.get("тип") for r in _геть_код}),
                                  приклади=[x["назва"][:40] for x in _геть_код[:3]]))
    # ── ТРАУРНИЙ РЕГІСТР — ТЕЖ СЦЕНА, І ДІЄ ДО ВІКОН (24.09.2026, рядок 154) ──
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ. Доти на нагоді «траур» пул рук 1–2 йшов тими самими
    # вікнами палітри, що й на побаченні: виміряно на похороні (сід 3, каталог_повний,
    # стенд_вх) — з 120 великих кандидатів руки 1 у регістрі за виміром 8, поза 92, а на
    # картку їхала світла фатинова «сукня-тістечко». Тепер святкова оздоба знімається в
    # усіх слотах, гучний візерунок — на великих поверхнях, явний глянець — біля обличчя,
    # а колір поверхні поза «темне й тихе» (колір найбільшої площі) — у речах, де регістр
    # міряє колір, разом із прикрасою не з металу (`траурний_регістр.траурне_відсічення`;
    # колір і межа речей — ті самі, що в суді K-OCC-01). Кожне зняття названо тут і
    # доливається в `відсічено` пакета (`міст_пакет._пакет_у_бюджет`).
    # ЧОГО НЕ ЧІПАЄ: речі без кольору (незнання не відсівається) і колір лише словом,
    # що здебільшого темний (суд скаже про нього «без входу», а не «так»). Бажання
    # жінки й обрана нею основа йдуть у пул повз цей фільтр — п.9.
    # траур — за заявою людини (`траур_заяви`, коли поломка руки 2 змінила нагоду)
    _тр = _ТР.траур_сцени(сцен or {})
    if _тр and _тр.get("лишилось"):
        import collections as _кол
        _лиш, _зняті = [], {}
        for r in речі:
            _п = _ТР.траурне_відсічення(r, _тр)
            if _п:
                _зняті.setdefault(_п, []).append(r)
            else:
                _лиш.append(r)
        for _п, _рч in sorted(_зняті.items(), key=lambda x: -len(x[1])):
            # рядок 205: причина — КОД `траурне_відсічення` як є (`mourning_*`), без
            # українського префікса: той самий ключ читає лічба `відсічено` й звіт власника
            відкинуто.append(dict(причина=_п, скільки=len(_рч),
                                  слоти=dict(_кол.Counter(r.get("слот") for r in _рч).most_common()),
                                  приклади=[(x.get("id"), str(x.get("назва") or "")[:50])
                                            for x in _рч[:3]]))
        речі = _лиш
    # ── ЧУЖИЙ КОЛІР ПОДІЇ — ДО ВІКОН (НП-в, рядок 522; K-KOH-08) ─────────────
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ. Доти майже-біле на весіллі гостею лише позначав суд, а пул
    # лишав його кандидатом руки 1 — модель брала білу сукню, суд її штрафував. Тепер
    # пул читає ЛИШЕ поле мовної моделі `зарезервований_колір` (вона знає, що жінка — гостя;
    # саме місце весілля цього не каже: наречена теж на весіллі), а дрес-код all-black
    # вето знімає, як у суді (`формальність.вето_майже_білого`). Велика поверхня, яку суд
    # назвав би «soft», до вікон не доходить. Бажання жінки йдуть повз фільтр (п.9).
    if (сцен or {}).get("зарезервований_колір") == "near_white" and _ФОРМ.вето_майже_білого(сцен):
        _білі = [r for r in речі if _ФОРМ.майже_біла_річ(r)]
        if _білі:
            _ід = {id(r) for r in _білі}
            речі = [r for r in речі if id(r) not in _ід]
            відкинуто.append(dict(причина="near_white_reserved", скільки=len(_білі),
                                  приклади=[(x.get("id"), str(x.get("назва") or "")[:50]) for x in _білі[:3]]))
    if жорстке_ні:
        речі, ні = PR.жорстке_ні_фільтр(речі, жорстке_ні)
        if ні: відкинуто.append(dict(причина="person_hard_no", скільки=len(ні),
                                     приклади=[x["назва"] for x in ні[:3]]))
    # ── КОМФОРТ ЯК НАМІР (K-PER-00 comfort_first, 19.09.2026) ────────────────
    # «Sensory and movement freedom as hard constraints» — тобто фільтр, як
    # жорстке «ні», а не вага. Стеля — `каблук_смуга_низ` (K-SHO-16, T2): від неї
    # вартість носіння починає рости, і під цим наміром жінка сказала, що платити
    # не хоче. Пара без висоти (каблук є, см нема) лишається: відкидати за
    # невідомим — вигадка, суд назве брак входу. Доти намір comfort_first модулю
    # був невідомий, і в пул ішли всі каблуки.
    _стеля_кл = _РЕЄСТР._намір((сцен or {}).get("intent"), (сцен or {}).get("мета_важливо"))["каблук_стеля"]
    if _стеля_кл:
        # ЧЕРЕЗ ФАСАД, А НЕ В ТІЛО ЧУЖОЇ ГІЛКИ (20.09.2026, рядок 91): `accessory`
        # реекспортує `C`, і гілка лишає за собою право пересунути таблицю всередині
        # себе. Імпорт лишається лінивим — цикл він і так не робить (перевірено
        # `склад`: з `accessory` композитор недосяжний), але ціна незмінна.
        import accessory as _АР
        _стеля = float(_АР.C[_стеля_кл])
        def _см(r):
            """Висота каблука в см або None; смуга крамниці читається НИЖНІМ краєм.

            Рядок 196: «більше 6 см» — це клас фільтра, не число, але край у нього
            доведений. Жорстке «ні» під `comfort_first` мусить його бачити, інакше
            пара на 10,5 см проходить лише тому, що крамниця не написала цифри.
            """
            import фід_взуття as _ФВ
            try: return _ФВ.висота_або_підлога(r)
            except (TypeError, ValueError, KeyError): return None
        _високі = [r for r in речі if r.get("слот") == "взуття"
                   and _см(r) is not None and _см(r) >= _стеля]
        if _високі:
            _ід = {id(r) for r in _високі}
            речі = [r for r in речі if id(r) not in _ід]
            # рядок 5440: причина — КОД (п.12), а звідки гілка — `гілка` кодом (`intent` чи `tile`): доти фраза
            # «каблук від … під наміром comfort_first» стояла й тоді, коли намір conventional, а діяла плитка
            відкинуто.append(dict(причина="heel_above_comfort_ceiling", правила=["K-PER-00", "K-SHO-16"],
                                  гілка=_РЕЄСТР.джерело_гілки((сцен or {}).get("intent"),
                                                              (сцен or {}).get("мета_важливо"), "каблук_стеля"),
                                  стеля_см=_стеля, скільки=len(_високі),
                                  приклади=["%s (%g см)" % (x["назва"][:34], _см(x)) for x in _високі[:3]]))
    if вето:
        # ── ВЕРХНІЙ ШАР СУДИТЬСЯ СВОЇМ СТАНОМ (рядок 1970) ─────────────────────
        # `O.елементи` за замовчуванням — «у приміщенні», а там верхнього шару не
        # видно (`continue`). Доти вето бачило лише речі в приміщенні, тож пальт
        # не було серед `чисті`, і БУДЬ-ЯКЕ вето зони знімало з пулу весь верхній
        # шар (стенд, −3 °C: 861 → 0 пальт), з порожніми `приклади`, бо знахідок
        # на них не було. Тепер пальта йдуть окремим викликом у стані «надворі»
        # (у списку лише пальта, тож правило «верх під застібнутим пальтом» не
        # ховає нічого), і вето знімає лише ту річ, що справді відкриває зону.
        def _ел(рр, **к):
            return O.елементи([dict(r, hex=r.get("hex") or "#808080", площа=0.3, near=0.3)
                               for r in рр], **к) if рр else []
        _пальта = [r for r in речі if r.get("слот") == "верхній_шар"]
        E = _ел([r for r in речі if r.get("слот") != "верхній_шар"]) + _ел(_пальта, стан="надворі")
        чисті, зн = _СУД.вето_покриття(E, вето=вето, тіло=тіло)
        лишились = {e.get("річ") or e.get("id") for e in чисті}
        нові = [r for r in речі if (r.get("id") in лишились or r.get("назва") in лишились)]
        if len(нові) != len(речі):
            # приклади — і тоді, коли річ випала без знахідки (вона мусить бути видна)
            _зн_ід, _нові = {(z.get("речі") or [None])[0] for z in зн}, {id(r) for r in нові}
            _тихі = [r.get("id") for r in речі if id(r) not in _нові and r.get("id") not in _зн_ід]
            відкинуто.append(dict(причина="вето покриття (K-PC-08)",
                                  скільки=len(речі) - len(нові),
                                  приклади=[z["суть"][:40] for z in зн[:3]] + _тихі[:3]))
        речі = нові
    return речі, відкинуто
