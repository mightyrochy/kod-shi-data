def людина(л):
    """ЛЮДИНА пакета → людина кодами: контраст, підтон, палітра (схема, ролі кольору за
    слотами, нейтралі й акценти «код #hex», метал, найдальші, поєднання, прийоми), тіло."""
    if not isinstance(л, dict):
        return л
    вих = {}
    if л.get("контраст"):
        вих["contrast"] = _з(_КОНТРАСТ, л["контраст"])
    if isinstance(л.get("світлота"), dict):
        вих["lightness"] = {{"шкіра": "skin", "волосся": "hair", "очі": "eyes"}.get(к, к): v
                            for к, v in л["світлота"].items()}
    т = л.get("температура")
    if isinstance(т, dict):
        вих["undertone"] = {"class": _з(_ТЕМПЕРАТУРА, т.get("клас")),
                            "from": _з(_ДЖЕРЕЛО_ТЕМПЕРАТУРИ, т.get("джерело"))}
    if isinstance(л.get("палітра"), dict):
        вих["palette"] = палітра(л["палітра"])
    т = л.get("тіло")
    if isinstance(т, dict):
        тіло = {}
        if т.get("зріст") is not None:
            тіло["height_cm"] = _число(т["зріст"])
        if т.get("ярлик"):
            # «H/X межа» — кодом HX, як у заявах суду (`силует_суд._літери_кодом`)
            тіло["shape"] = "HX" if т["ярлик"] == "H/X межа" else т["ярлик"]
        if т.get("зони"):
            тіло["zones"] = {{"верх_проти_низу": "top_vs_bottom", "талія_виражена": "waist_defined"}.get(к, к):
                             _число(v) for к, v in т["зони"].items()}
        вих["body"] = тіло
    return вих


def палітра(п):
    """Палітра (`ЛЮДИНА.палітра`, `ОПИС_V1.палітра`) → кодами: схема, ролі кольору за слотами
    схеми, нейтралі й акценти «код #hex», метал, найдальші, поєднання, прийоми."""
    if not isinstance(п, dict):
        return п
    пал = {}
    if п.get("схема"):
        пал["scheme"] = _з(_СХЕМА, п["схема"])
    if п.get("ролі_слотів"):
        пал["slot_roles"] = {код("slot", с): _з(_РОЛЬ, р) for с, р in п["ролі_слотів"].items()}
    for к, ключ in (("нейтралі", "neutrals"), ("акценти", "accents")):
        if п.get(к):
            пал[ключ] = [колір_з_hex(x) for x in п[к]]
    if п.get("метал"):
        пал["metal"] = _з(_МЕТАЛ, п["метал"])
    if п.get("найдальші"):
        пал["farthest"] = [_з(_ОСІ_ПАЛІТРИ, x.strip()) for x in str(п["найдальші"]).split(",") if x.strip()]
    if п.get("поєднання"):
        пал["combinations"] = [dict({"technique": _з(_ПРИЙОМ, x.get("прийом"))} if x.get("прийом") else {},
                                    colors=[колір_з_hex(к) for к in (x.get("кольори") or [])])
                               for x in п["поєднання"] if isinstance(x, dict)]
    if п.get("прийоми"):
        пал["techniques"] = []
        for x in п["прийоми"]:
            if isinstance(x, dict):
                т = _з(_ПРИЙОМ, x.get("прийом"))
                суть = СУТЬ_ПРИЙОМУ_EN.get(т) or x.get("суть")
                пал["techniques"].append(dict({"technique": т}, **({"gist": суть} if суть else {})))
    # ── ОСНОВА ОБРАЗУ — КОДАМИ, А НЕ УКРАЇНСЬКИМИ КЛЮЧАМИ (рядок 171 дошки) ──────
    # Доти `основа` падала в «як є» нижче й доїжджала до англійського промпта рук 1–2
    # словником `{"слово":"хакі","hex":"#a0aa8d","джерело":"стилістка обрала під цей вихід"}`:
    # ключі кирилицею, значення — фразою коду. Колір пишеться тим самим записом, що нейтралі
    # й акценти («code #hex»), а хто обрав — кодом із `_ОСНОВУ_ОБРАВ`.
    if isinstance(п.get("основа"), dict):
        о = п["основа"]
        _колір = " ".join(str(x) for x in (о.get("слово"), о.get("hex")) if x)
        пал["base"] = {к: v for к, v in (("colour", колір_з_hex(_колір) if _колір else None),
                                         ("chosen_by", _з(_ОСНОВУ_ОБРАВ, о.get("джерело")))) if v}
    for к, v in п.items():                  # поле, якого перелік вище не знає, — як є
        if к not in ("схема", "ролі_слотів", "нейтралі", "акценти", "метал", "найдальші",
                     "поєднання", "прийоми", "основа") and v not in (None, "", [], {}):
            пал[к] = v
    # СЛОВА КОЛЬОРІВ — КОДАМИ (ПР-10, п.12). `palettes.для_пакета` кладе в `accent_families`,
    # `neutral_axes` і `wardrobe_season` слова лексикону («м'ятний», «срібний»), бо дописати
    # переклад у дріт тоді не можна було (К-3); у промпт вони їхали кирилицею. Слово без коду
