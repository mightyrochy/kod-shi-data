def _число(v):
    """3.0 → 3; інше число — як є (до трьох знаків: WHR 0.747 — факт, а не шум); не число — як є."""
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        return v
    return int(v) if float(v).is_integer() else round(float(v), 3)


def код(поле, v):
    """Слово ядра → код таблиці `поле`; «невідомо» → unknown; поза таблицею — як є."""
    if v is None:
        return None
    if isinstance(v, str) and _ВМ.невідомо(v):
        return U
    return _ВМ.код(поле, v) or _ВМ.код(поле, str(v).replace(" ", "_")) or v


def _з(мапа, v):
    """Значення закритого переліку `мапа` → код; поза переліком — як є."""
    return мапа.get(v, v) if isinstance(v, str) else v


