def колір_код(слово):
    """Слово кольору → (код `color_name` або None, слово крамниці, коли воно каже більше за код).
    Слово поза таблицею («зелена», «беж», «айворі») читає нормалізатор ядра `verify.назва_кольору`
    (корінь на межі слова → слово лексикону). Слово крамниці лишається поруч із кодом, лише коли
    воно не форма того самого слова («світло-сірий», «айворі», «гіркий шоколад»; «зелена» — ні)
    або коли коду нема зовсім («капучіно»): це її факт про колір, як назва — факт про річ."""
    if not слово:
        return None, None
    if _ВМ.невідомо(str(слово)):
        return U, None
    прямо = _ВМ.код("color_name", слово)
    if прямо:
        return прямо, None
    import verify as _V
    лекс = _V.назва_кольору(str(слово))
    к = _ВМ.код("color_name", лекс) if лекс else None
    с = str(слово).strip().lower()
    спільне = len(_os.path.commonprefix([с, лекс or ""]))
    форма = bool(к) and not _re.search(r"[\s-]", с) and спільне >= max(3, min(len(с), len(лекс)) - 2)
    return к, (None if форма else str(слово))


def колір_з_hex(рядок):
    """«срібний #c1baac» → «silvery #c1baac»: слово палітри кодом, hex — як є."""
    м = _re.match(r"^(.*?)\s*(#[0-9a-fA-F]{6})$", str(рядок or "").strip())
    if not м:
        return код("color_name", рядок)
    return ("%s %s" % (код("color_name", м.group(1)), м.group(2))).strip()


def _тип(v):
    """Тип речі кодом; «сумка»/«шарф»/«прикраса» без уточнення — їхні коди «_generic»."""
    if not v:
        return None
    return (_ВМ.код("item_type", v) or _ВМ.код("item_type", "%s_без_уточнення" % v) or v)


def _межа_типу(v):
    """Тип речі в її межі («Не хоче») кодом: тип речі, інакше ознака («підбори» → heels), інакше як є."""
    if not v:
        return None
    return _ВМ.код("item_type", v) or _ВМ.код("feature", v) or _тип(v)


