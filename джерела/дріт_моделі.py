# стилістка мала б звіряти арифметикою; «neat» проти «["everyday","neat"]» — та сама міра
# словом. Чисел шкали на дроті нема (`проби/нг3_числа_в_дроті.py`).
def щаблі(інтервал):
    """[від, до] шкали 1–10 → [код від, код до]; обидва кінці на одному щаблі — один код.
    Не пара чисел — як є (невідоме лишається невідомим)."""
    if isinstance(інтервал, (list, tuple)) and len(інтервал) == 2:
        к = [_БР.щабель_код(x) for x in інтервал]
        if all(к):
            return к[0] if к[0] == к[1] else к
    return інтервал


def ошатність_словом(v):
    """Значення на шкалі 1–10 (число чи пара) → код щабля чи пара кодів; інше — як є."""
    return _БР.щабель_код(v) or щаблі(v)


