_ЧАСТИНА = {"верх": "top", "низ": "bottom"}


def опис(об):
    """`ОПИС_V1` обʼєктом коду → дані промпта опису: образ (речі з номером, назвою, крамницею,
    кольором кодом, номерами фото; без слота), задум, твої оголошені ходи, способи носіння,
    випадок, день, твоє речення про день, палітра, її межі, чого в образі нема."""
    об = об or {}
    о = об.get("образ") or {}
    рч = []
    for x in (о.get("речі") or []):
        р = {"n": x.get("н"), "name": x.get("назва")}
        for ключ, v in (("set_half", _з(_ЧАСТИНА, x.get("частина"))), ("shop", x.get("магазин")),
                        ("color", код("color_name", x.get("колір")) if x.get("колір") else None),
                        ("hex", x.get("hex")), ("photos", x.get("фото_номери")),
                        ("hers", True if x.get("її_річ") else None)):
            if v not in (None, "", []):
                р[ключ] = v
        рч.append(р)
    вих = {"outfit": {"id": о.get("ід"), "items": рч}}
    for к, ключ in (("задум", "idea"), ("випадок", "case"), ("день", "day"),
                    ("день_образу", "your_day_sentence"), ("свідомі", "your_declared"),
                    ("межі", "she_refuses"), ("неповний", "missing")):
        if об.get(к):
            вих[ключ] = об[к]
    if об.get("укладка"):
        вих["ways_to_wear"] = [{"item": x.get("річ"), "options": x.get("опції")}
                               for x in об["укладка"] if isinstance(x, dict)]
    if об.get("палітра"):
        вих["palette"] = палітра(об["палітра"])
    return вих


