def _дрес_код(v):
    """Дрес-код кодом; підпис плитки («Буденно») — ключем, чий це підпис (`ДОВІДНИК_ПІДПИСИ`)."""
    к = код("dress_code", v)
    if к != v:
        return к
    for ключ, (підпис, _нота) in (_ПО.ДОВІДНИК_ПІДПИСИ.get("коди") or {}).items():
        if v == підпис:
            return код("dress_code", ключ)
    return v


def випадок(в, день=None):
    """ВИПАДОК пакета → випадок кодами; поля, які несе `день`, — лише коли дня нема.
    `рядок` (той самий випадок реченням коду) не йде: його факти — у полях поруч."""
    if not isinstance(в, dict):
        return в
    вих = {к: в[к] for к in ("field_quotes", "wish_quotes", "formality_reason") if в.get(к)}
    for к, v in в.items():
        if к not in ПОЛЯ_ВИПАДКУ or v in (None, "", [], {}):
            continue
        if день and к in _ВИПАДОК_У_ДНІ and _ВИПАДОК_У_ДНІ[к] in день:
            continue
        # подія, якої вона не називала (`випадок_для_пакета`: «невідомо»), не їде: нагода
        # й місце стоять поруч кодами
        if к == "подія" and isinstance(v, str) and _ВМ.невідомо(v):
            continue
        ключ = ПОЛЯ_ВИПАДКУ[к]
        if к == "нагода":
            v = код("occasion", v)
        elif к == "місце":
            v = код("place", v)
        elif к == "формат":
            v = код("setting", v)
        elif к == "рух":
            v = код("movement", v)
        elif к == "дрес_код":
            v = _дрес_код(v)
        elif к == "опади":
            v = код("precipitation", v)
        elif к == "мета":
            v = код("goal", v)
        elif к == "мета_зони":
            v = [код("goal_zone", x) for x in v]
        elif к == "мета_важливо":
            v = [код("goal_extra", x) for x in v]
        elif к == "прикраси":
            v = код("jewelry", v)
        elif к == "намір":
            v = код("intent", v)
        elif к == "прохання_взуття":
            v = код_переліку(_ПРОХАННЯ_ВЗУТТЯ, v)
        elif к == "реєстр_людини":
            v = [код("register", x) for x in v]
        elif к == "ошатність":
            v = [_число(x) for x in v]
        elif к == "макіяж" and isinstance(v, dict):
            v = {кк: vv for кк, vv in (("level", код("makeup_level", v.get("рівень"))), ("lips", v.get("губи"))) if vv}
        elif к == "вето" and isinstance(v, dict):
            # МЕЖА НА ОДИН СЛОТ — ОБʼЄКТОМ {code, only_on}: слот, на якому код її тримає
            # (`випадок.вето.слоти`); межа без слота — голим кодом, про весь образ
            сл = v.get("слоти") or {}
            на = lambda x, c: ({"code": c, "only_on": [код("slot", s) for s in сл[x]]} if сл.get(x) else c)
            v = {кк: vv for кк, vv in (
                ("types", [_межа_типу(x) for x in (v.get("типи") or [])]),
                ("fabrics", [на(x, код("fabric", x)) for x in (v.get("тканини") or [])]),
                ("prints", [на(x, код("pattern", x)) for x in (v.get("принти") or [])]),
                ("colors", [на(x, код("color_class", x) if _ВМ.код("color_class", x) else код("color_name", x))
                            for x in (v.get("кольори") or [])]),
                ("zones", [код("zone", x) for x in (v.get("зони") or [])])) if vv}
            if not v:
                continue
        elif к == "невідомо":
            v = [ПОЛЯ_ВИПАДКУ.get(x, x) for x in v]
        elif isinstance(v, (int, float)) and not isinstance(v, bool):
            v = _число(v)
        вих[ключ] = v
    return вих


