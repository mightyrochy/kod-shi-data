def _стиснути(ключ, v):
    """Та сама заява легшою формою — і тільки там, де вона й справді та сама.

    `veto` після відсіву «нема ознаки» (`каталог_коди.ПОРОЖНІ`) лишає самі «yes», тож обʼєкт
    {ключ: "yes"} каже рівно те, що перелік ключів: `{"tight":"yes"}` → `["tight"]`.
    Список з однієї назви — сама назва: `["polyester"]` → `"polyester"`. Обидва — форма, не
    зміст: жодної заяви не зникає, і назад вони читаються однозначно."""
    if ключ == "veto" and isinstance(v, dict):
        return sorted(v) or None
    if isinstance(v, list) and len(v) == 1 and isinstance(v[0], str):
        return v[0]
    return v


# Пара «від…до» з однаковими кінцями — одне число: у більшості речей пулу `L` — [a, a], і друге
# число — кілька токенів ні про що. Ключі — повні й короткі.
_ПАРИ_ВІД_ДО = ("L", "hem_cm")


def _легше(о):
    """Річ пулу тією самою заявою легшою формою (`_стиснути`, пара з однаковими кінцями —
    число); ключі й порядок ті самі. Пул складання, склад образу й вітрина вердикта;
    опис і далі отримує запис як є."""
    вих = dict(о)
    for к, v in о.items():
        if not isinstance(v, (list, dict)):       # число, рядок, так/ні — уже найлегша форма
            continue
        if к in _ПАРИ_ВІД_ДО and len(v) == 2 and v[0] == v[1]:
            v = v[0]
        v = _стиснути(к, v)
        if v in (None, "", [], {}):
            del вих[к]
        else:
            вих[к] = v
    return вих


def _скоротити(о):
    """Значення речі — стиснутими (`_стиснути`), порядок і ключі ті самі."""
    вих = {}
    for к, v in о.items():
        v = _стиснути(к, v)
        if v not in (None, "", [], {}):
            вих[к] = v
    return вих


