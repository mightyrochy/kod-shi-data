# «["everyday","neat"]»: та сама міра словом. Виміряно `проби/нг3_числа_в_дроті.py` (4 сценарії,
# складання · ремонт · вибір): чисел шкали 440–468 · 48–56 · 24–32 → 0.
def щаблі(інтервал):
    """[від, до] шкали 1–10 → [код від, код до]; обидва кінці на одному щаблі — один код.
    Не пара чисел — як є (невідоме лишається невідомим)."""
    if isinstance(інтервал, (list, tuple)) and len(інтервал) == 2:
        к = [_БР.щабель_код(x) for x in інтервал]
        if all(к):
            return к[0] if к[0] == к[1] else к
    return інтервал


def ошатність_словом(v):
    """Значення на шкалі 1–10 (число чи пара) → код щабля чи пара кодів; інше — як є."""
    return _БР.щабель_код(v) or щаблі(v)


def день_на_дріт(д):
    """`сценарій.день_кодами` → день на дріт: смуга нагоди кодами щаблів (`from`, `to`), решта як є."""
    if not (isinstance(д, dict) and isinstance(д.get("formality"), dict)):
        return д
    ф = д["formality"]
    return dict(д, formality={к: ошатність_словом(v) for к, v in ф.items()})


