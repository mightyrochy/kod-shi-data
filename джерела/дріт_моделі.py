def заяви(список):
    """Заяви внутрішньою мовою (`{code, values}`) → ті самі заяви на дріт, СТИСЛО: заява без
    значень — сам код рядком, зі значеннями — `{код: значення}` (числа числами, коди кодами,
    вільний текст — `{free_text, lang}`). Зміст той самий, що в `{code, values}`, без двох
    службових ключів на кожній заяві: їх на промпт сотні, і вони коштували б вікна моделі
    (виміряно `проби/дріт_заяви_лічба.py` разом із токенами, П-6). Що означає код — один
    словник промпта (`збирач_промптів`, `task.statement_codes`)."""
    return [({x["code"]: x["values"]} if x.get("values") else x["code"])
            for x in (список or []) if isinstance(x, dict) and x.get("code")]


def _знахідка(z, склад=None, ремонти=None):
    """Знахідка на дроті → англійська: вага, регістр кодом, що знайдено й ремонт.
    `сила` (слово) не йде — те саме, що `сила_нп`; `свідомий` — лише коли true.
    `ремонти` — легенда вердикта: однаковий текст ремонту їде один раз, знахідка — його ключ.

    П-6 (CLAUDE.md п.12): знахідка, що несе ЗАЯВИ, їде кодами — `statements` (що знайдено) і
    `fix` (ремонт) списками `{code, values}`; що означає кожен код, модель читає в одному
    словнику промпта (`збирач_промптів`, `task.statement_codes`). Прози коду `what` і тексту
    ремонту поруч нема — ті самі слова лишаються діагнозом звіту власника. Знахідка без заяв —
    як доти, суть і ремонт словами (`проби/дріт_заяви_лічба.py` лічить таких)."""
    if not isinstance(z, dict):
        return z
    о = {"id": z.get("ід")}
    if z.get("сила_нп") is not None:
        о["weight"] = z["сила_нп"]
    # РЕГІСТР — ЛИШЕ НЕ ТИПОВИЙ (П-6, бюджет промпту): репліка — типовий регістр знахідки на
    # дроті, і «remark» на кожній із десятків знахідок нічого моделі не каже; їде «gate» (те,
    # що мусить зникнути) і будь-що інше. Рядок входу оголошень це й називає.
    if z.get("регістр") and z["регістр"] != "репліка":
        о["register"] = _з(_РЕГІСТР_ЗНАХІДКИ, z["регістр"])
    if z.get("заяви"):
        о["statements"] = заяви(z["заяви"])
    elif z.get("суть"):
        о["what"] = z["суть"]
    if z.get("ремонт_заяви") and ремонти is not False:
        о["fix"] = заяви(z["ремонт_заяви"])
    elif z.get("ремонт") and ремонти is not False and not z.get("заяви"):
        # знахідка кодами прози ремонту не везе й тоді, коли ремонту кодом у неї нема
        # (акцент в оголошеному фокусі: ремонтувати нічого) — інакше код заговорив би
        # з моделлю двома мовами в одному вузлі
        о["fix"] = (ремонти.setdefault(z["ремонт"], "r%d" % (len(ремонти) + 1))
                    if ремонти is not None else z["ремонт"])
    if z.get("злито"):
        о["merged"] = z["злито"]
    рч = [_номер(x) for x in (z.get("речі") or [])]
    if рч:
        о["items"] = [x if (склад is None or x in склад or not isinstance(x, str) or not x.startswith("#"))
                      else next((dict(n=y.get("н"), name=y.get("назва")) for y in (z.get("речі") or [])
                                 if isinstance(y, dict) and y.get("н") == x), x)
                      for x in рч]
    if z.get("свідомий"):
        о["declared"] = True
    return о


def _чекліст(ч, скрізь):
    """Чекліст образу → англійський; назви неперевірених пунктів, спільні для ВСІХ образів
    вердикта, стоять один раз у корені (`скрізь`), тут — лише ті, що понад них."""
    вих = {}
    for бік, п in (ч or {}).items():
        if not isinstance(п, dict):
            continue
        б = {"надлишок": "excess", "прісність": "blandness", "палітра": "palette",
             "аксесуари": "accessories"}.get(бік, бік)   # ПР-10: «аксесуари» доїжджав кирилицею
        о = {}
        if п.get("провал"):
            о["failed"] = list(п["провал"])
        for к, ключ in (("пройдено", "passed"), ("без_входу", "no_input")):
            if п.get(к) is not None:
                о[ключ] = п[к]
        понад = [x for x in (п.get("вимкнено") or []) if x not in скрізь.get(б, ())]
        if понад:
            о["not_run"] = понад
        вих[б] = о
    return вих


def вердикт(в, ремонти=True, межі=None):
    """Вердикт на дроті (`протокол.вердикт_на_дріт` без кодів правил) → англійський дріт.
    `ремонти=False` — знахідки без тексту ремонту (вибір не ремонтує); `межі` — її межі
    словами (`she_refuses`), коли задача їх читає.

    Той самий зміст, три стиснення без втрат: (1) річ у суді — номером: її повний опис стоїть
    у складі того самого образу; (2) текст ремонту, однаковий у кількох знахідках, — один
    раз у легенді `fixes`, знахідка несе його ключ; (3) назви пунктів чекліста, яких код
    не перевірив у ЖОДНОМУ з образів, — один раз у корені `not_run_everywhere`."""
    if not isinstance(в, dict):
        return в
    ремонти = {} if ремонти else False
    суд = [с for с in (в.get("вердикт") or []) if isinstance(с, dict)]
    скрізь = {}
    for бік, б in (("надлишок", "excess"), ("прісність", "blandness"), ("палітра", "palette")):
        множини = [set(((с.get("чекліст") or {}).get(бік) or {}).get("вимкнено") or []) for с in суд]
        if множини and all(множини):
            спільні = set.intersection(*множини)
            перший = ((суд[0].get("чекліст") or {}).get(бік) or {}).get("вимкнено") or []
            if спільні:
                скрізь[б] = [x for x in перший if x in спільні]
    вих = {}
    if в.get("версія"):
        вих["version"] = в["версія"]
    if в.get("ітерація"):
        вих["iteration"] = в["ітерація"]
    if в.get("випадок"):
        вих["case"] = в["випадок"]
    if в.get("день"):
        вих["day"] = в["день"]
    вих["verdict"] = []
    for с in суд:
        т = с.get("твій_образ") or {}
        склад = [x.get("н") if isinstance(x, dict) else x for x in (т.get("речі") or [])]
        о = {"your_outfit": {к2: v for к2, v in (("id", т.get("ід")), ("caption", т.get("підпис")),
                                                 ("items", [річ(x) if isinstance(x, dict) else x
                                                            for x in (т.get("речі") or [])]),
                                                 ("day", т.get("день"))) if v not in (None, "", [])}}
        ст = с.get("структура")
        if isinstance(ст, dict):
            о["structure"] = {"ok": ст.get("ок")}
            if ст.get("блокери"):
                # П-6: блокер із заявами їде кодами (`statements`), без рядка коду `what`
                о["structure"]["blockers"] = [
                    {к2: v for к2, v in (("id", б.get("ід")), ("code", _з(_БЛОКЕР, б.get("код"))),
                                         ("items", [_номер(x) for x in (б.get("речі") or [])]),
                                         ("statements", заяви(б.get("заяви"))),
                                         ("what", None if б.get("заяви") else б.get("суть")))
                     if v not in (None, "", [])}
                    for б in ст["блокери"] if isinstance(б, dict)]
        if с.get("знахідки"):
            о["findings"] = [_знахідка(z, склад, ремонти) for z in с["знахідки"]]
        if с.get("свідомі"):
            # ПР-10: без «text» — це «назва — чому» тими самими словами, що вже стоять у «item» і
            # «why» (назва речі — у «your_outfit»); доти кожен свідомий хід їхав двічі
            о["your_declared"] = [{к2: v for к2, v in (("item", _номер(x.get("річ"))), ("why", x.get("чому")))
                                   if v}
                                  for x in с["свідомі"] if isinstance(x, dict)]
        if с.get("чекліст"):
            о["checklist"] = _чекліст(с["чекліст"], скрізь)
        if isinstance(с.get("вузол"), dict):
            # П-6: вузол із заявами їде кодами (що вузько, з чим зв'язано, що міняти)
            о["knot"] = ({"statements": заяви(с["вузол"]["заяви"])} if с["вузол"].get("заяви") else
                         {"name": с["вузол"].get("назва"), "why": с["вузол"].get("чому")})
        if с.get("виконання"):
            о["done_check"] = [{к2: v for к2, v in (("finding", x.get("знахідка")), ("action", x.get("дія")),
                                                    ("verified", x.get("перевірено")), ("why", x.get("чому")))
                                if v is not None and v != ""}
                               for x in с["виконання"] if isinstance(x, dict)]
        вих["verdict"].append(о)
    н = в.get("набір")
    if isinstance(н, dict):
        набір = {}
        р = н.get("різноманітність")
        if isinstance(р, dict):
            набір["variety"] = {к2: v for к2, v in (("ok", р.get("ок")), ("groups", р.get("групи")),
                                                    ("why", р.get("чому"))) if v is not None}
        г = н.get("герой")
        if isinstance(г, dict):
            набір["hero"] = {к2: v for к2, v in (("ok", г.get("ок")),
                                                 ("outfits_without_hero", г.get("образи_без_героя")),
                                                 ("outfits_with_two", г.get("образи_з_двома"))) if v is not None}
        if н.get("координація"):
            набір["coordination"] = [{к2: v for к2, v in (("id", x.get("ід")), ("rank", x.get("ранг")),
                                                          ("side", _з(_БІК, x.get("бік")))) if v is not None}
                                     for x in н["координація"] if isinstance(x, dict)]
        if н.get("невиконано"):
            набір["not_done"] = list(н["невиконано"])
        if н.get("знахідки"):
            набір["findings"] = [_знахідка(z, None, ремонти) for z in н["знахідки"]]
        вих["set"] = набір
    if скрізь:
        вих["not_run_everywhere"] = скрізь
    if ремонти:
        вих["fixes"] = {к2: т for т, к2 in ремонти.items()}
    if в.get("вітрина"):
        вих["showcase"] = пул(в["вітрина"])
    if в.get("слот_розриву"):
        вих["break_kind"] = код("slot", в["слот_розриву"])
    м = в.get("мова")
    if isinstance(м, dict):
        вих["language"] = {"can_show": м.get("можна_видавати"),
                           "violations": [{к2: v for к2, v in (("what", x.get("суть")), ("instead", x.get("натомість"))) if v}
                                          for x in (м.get("порушення") or []) if isinstance(x, dict)]}
    р = в.get("реєстр")
    if isinstance(р, dict):
        вих["register"] = {к2: v for к2, v in (("leading", реєстр(р.get("провідний"))),
                                               ("near", [реєстр(x) for x in (р.get("поруч") or [])])) if v}
    з = в.get("завдання")
    if isinstance(з, dict) and з.get("образів"):
        вих["outfits_wanted"] = з["образів"]
    _м = [str(x).strip() for x in (межі or []) if str(x or "").strip()]
    if _м:
        вих["she_refuses"] = _м
    if в.get("бракує"):
        вих["still_missing"] = [
            {к2: v for к2, v in (("outfit", б.get("образ")), ("items", б.get("речі")),
                                 ("empty_kinds", {код("slot", с): н for с, н in (б.get("порожні") or {}).items()}),
                                 ("same_kind", б.get("двічі"))) if v}
            for б in в["бракує"] if isinstance(б, dict)]
    return вих


