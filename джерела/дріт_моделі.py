# Тип знімається, наприклад, з поясів «пальто» чи «кардиган», низу «жилет», взуття «шуба».
_РОДИ_ПОРУЧ = {frozenset(("top", "outerwear"))}
_РОДИ_ПРИКРАС = frozenset(("jewelry", "necklace", "collar_necklace", "bracelet", "earrings", "brooch", "ring"))


def _тип_свого_роду(тип, рід):
    """Код типу, коли він не належить іншому роду за `СЛОТ_ТИПУ`; інакше None."""
    свій = _ВМ.СЛОТ_ТИПУ.get(тип or "")
    if (not тип or not рід or not свій or свій in (рід, "set") or frozenset((свій, рід)) in _РОДИ_ПОРУЧ
            or {свій, рід} <= _РОДИ_ПРИКРАС):
        return тип
    return None


def палітра_опису(пал):
    """Палітра на дроті → лише те, на що посилається поле «palette» опису: метал, найдальші, поєднання.

    Опис не дістає всієї палітри складання — прийомів з «gist», `accent_families`,
    `neutral_axes`, `axes`, `window`, `wardrobe_season`, `calibration`: на них жодне правило
    опису не посилається (ОПИС-1)."""
    if not isinstance(пал, dict):
        return пал
    return {к: пал[к] for к in ("metal", "farthest", "combinations") if пал.get(к)}


def опис(об):
    """`ОПИС_V1` обʼєктом коду → дані промпта опису: образ (речі з номером, родом і типом кодом, назвою,
    крамницею, одним кольором кодом, номерами фото), твої оголошені ходи, способи носіння (номером
    речі), випадок, день, палітра (метал, найдальші, поєднання), її межі, чого в образі нема."""
    об = об or {}
    о = об.get("образ") or {}
    рч = []
    for x in (о.get("речі") or []):
        р = {"n": x.get("н"), "name": x.get("назва")}
        # колір — кодом, слово крамниці — окремо, як у пулі (`колір_код`): інакше «Сірий» і
        # «світло сірий» стояли б у `color` поруч із `light_blue` сусідньої речі
        # рід і тип речі — лише кодом таблиці; слово поза таблицею не їде (п.12)
        _рід = _ВМ.код("slot", x["слот"]) if x.get("слот") else None
        # ЖОДНОГО КОЛЬОРУ, КОЛИ КАДР ІНШИЙ: другий колір поруч (`photo_colour: green` біля
        # `color: purple`) опис переказував би жінці («здається зеленим, але ми обираємо його як фіолетовий»), а
        # один колір слова дав би «бежеві туфлі» під шоколадним кадром картки. Код не знає, котрий із
        # двох вона отримає, тож їде лише позначка про кадр; `hex` чужого кадру — теж ні
        _інший_кадр = bool(x.get("кадр_колір"))
        for ключ, v in (("kind", _рід),
                        ("type", _тип_свого_роду(_ВМ.код("item_type", x["тип"]) if x.get("тип") else None, _рід)),
                        ("set_half", код_переліку(_ЧАСТИНА, x.get("частина"))), ("shop", x.get("магазин")),
                        # кадр іншого кольору: який колір вона отримає, код не знає (вікно
                        # слова й кадру разом, `фід_кадр_колір.вікно_з_кадром`), тож колір не їде зовсім —
                        # опис не назве річ кольором, який спростовує її ж кадр на картці
                        ("color", None if _інший_кадр else колір_код(x.get("колір"))[0]),
                        ("shop_color", None if _інший_кадр else колір_код(x.get("колір"))[1]),
                        ("hex", None if _інший_кадр else _КР_ТИП.hex_кольору(x)),
                        ("photo_other_colour", True if _інший_кадр else None),
                        ("photos", x.get("фото_номери")), ("no_photo", True if x.get("без_кадру") else None),
                        ("hers", True if x.get("її_річ") else None)):
            if v not in (None, "", []):
                р[ключ] = v
        рч.append(р)
    # ід образу латинкою (ВМ-3б): «о4» → «o4», як у вердикті й пакеті (`протокол.ід_на_дріт`)
    вих = {"outfit": {"id": _ПР.ід_на_дріт(о.get("ід")), "items": рч}}
    # підпис (`задум`) і речення про день (`день_образу`) моделі не їдуть: писані до ремонту й
    # заміни, вони називали б речі поза складом («Softened by Scarf» без шарфа), а код прози не читає (п.12)
