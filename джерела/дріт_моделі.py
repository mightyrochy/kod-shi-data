def випадок(в, день=None):
    """ВИПАДОК пакета → випадок кодами; поля, які несе `день`, — лише коли дня нема.
    `рядок` (той самий випадок реченням коду) не йде: його факти — у полях поруч."""
    if not isinstance(в, dict):
        return в
    вих = {}
    for к, v in в.items():
        if к not in _ПОЛЯ_ВИПАДКУ or v in (None, "", [], {}):
            continue
        if день and к in _ВИПАДОК_У_ДНІ and _ВИПАДОК_У_ДНІ[к] in день:
            continue
        ключ = _ПОЛЯ_ВИПАДКУ[к]
        if к == "нагода":
            v = код("occasion", v)
        elif к == "місце":
            v = код("place", v)
        elif к == "формат":
            v = код("setting", v)
        elif к == "рух":
            v = код("movement", v)
        elif к == "дрес_код":
            v = _дрес_код(v)
        elif к == "опади":
            v = код("precipitation", v)
        elif к == "мета":
            v = код("goal", v)
        elif к == "прикраси":
            v = код("jewelry", v)
        elif к == "намір":
            v = код("intent", v)
        elif к == "прохання_взуття":
            v = _з(_ПРОХАННЯ_ВЗУТТЯ, v)
        elif к == "реєстр_людини":
            v = [код("register", x) for x in v]
        elif к == "ошатність":
            v = [_число(x) for x in v]
        elif к == "макіяж" and isinstance(v, dict):
            v = {кк: vv for кк, vv in (("level", код("makeup_level", v.get("рівень"))), ("lips", v.get("губи"))) if vv}
        elif к == "вето" and isinstance(v, dict):
            v = {кк: vv for кк, vv in (
                ("types", [_межа_типу(x) for x in (v.get("типи") or [])]),
                ("fabrics", [код("fabric", x) for x in (v.get("тканини") or [])]),
                ("prints", [код("pattern", x) for x in (v.get("принти") or [])]),
                ("colors", [код("color_class", x) if _ВМ.код("color_class", x) else код("color_name", x)
                            for x in (v.get("кольори") or [])]),
                ("zones", [код("zone", x) for x in (v.get("зони") or [])])) if vv}
            if not v:
                continue
        elif к == "невідомо":
            v = [_ПОЛЯ_ВИПАДКУ.get(x, x) for x in v]
        elif isinstance(v, (int, float)) and not isinstance(v, bool):
            v = _число(v)
        вих[ключ] = v
    return вих


def людина(л):
    """ЛЮДИНА пакета → людина кодами: контраст, підтон, палітра (схема, ролі кольору за
    слотами, нейтралі й акценти «код #hex», метал, найдальші, поєднання, прийоми), тіло."""
