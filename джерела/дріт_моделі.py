def полюси(п, образів=None):
    """`ПАКЕТ_V1.полюси` → [{id, idea}] кодами; вільний полюс — скільки образів без заданого
    задуму (усі замовлені образи мінус названі задуми)."""
    import протокол as _ПР
    вих, названих = [], 0
    for x in (п or []):
        ід = x.get("ід")
        if ід == _ПР.ПОЛЮС_ВІЛЬНИЙ:
            continue
        названих += 1
        вих.append({"id": _ПР.ЗНАЧЕННЯ_ВІДПОВІДІ_EN["полюс"].get(ід, ід),
                    "idea": ЗАДУМ_EN.get(ід) or x.get("опис")})
    вільних = max(0, int(образів or 0) - названих)
    if any(x.get("ід") == _ПР.ПОЛЮС_ВІЛЬНИЙ for x in (п or [])) and вільних:
        вих.append({"id": "free", "outfits": вільних,
                    "idea": "your own ideas; caption each so that its idea shows"})
    return вих


def пакет(п):
    """ПАКЕТ_V1 обʼєктом коду → дані промпта складання кодами: випадок, день, людина, пул одним
    переліком (комплект — `two_piece`, слота нема), межі складання полями, її речі номерами,
    правила корпусу рядками, задуми, недосяжні задуми, скільки образів."""
    п = п or {}
    день = п.get("день")
    вих = {}
    if п.get("випадок"):
        вих["case"] = випадок(п["випадок"], день)
    if день:
        вих["day"] = день
    if п.get("людина"):
        вих["person"] = людина(п["людина"])
        # МЕТАЛ У ПРОМПТІ СКЛАДАННЯ — ОДИН (рядок 481, ВМ-1): заява `jewellery_metal` у
        # `style_rules` (самозвіт → метал практичної палітри, `brief.бриф`). Той самий метал
        # полем палітри й прийом «metal by colour temperature … neutral — both» були другою й
        # третьою відповіддю на одне питання. Вимкнене правило металу руки 2 (Р2-2а) знімає
        # рядок брифа — і тоді металу в промпті нема зовсім, як і задумано.
        _пал = (вих["person"] or {}).get("palette") if isinstance(вих["person"], dict) else None
        if isinstance(_пал, dict):
            _пал.pop("metal", None)
            if isinstance(_пал.get("techniques"), list):
                _пал["techniques"] = [т for т in _пал["techniques"]
                                      if not (isinstance(т, dict) and т.get("technique") == "metal")]
    # ── ДЕ САМЕ ДІЄ КОРОТКИЙ ЗАПИС (К-3): ТІЛЬКИ ТУТ, У ПУЛІ СКЛАДАННЯ ──────────
    # Бюджет символів ріже САМЕ пул (`міст_пакет._пакет_у_бюджет` бінарно шукає, скільки
    # речей влазить у 120 000 символів ЦЬОГО тексту), тож коротший запис речі тут — це
    # більше речей у тому самому запиті. Прапорець стоїть у `завдання` пакета, а не в
    # оточенні модуля: на чому зібрано цей пул, має бути видно в самому пакеті — його
    # читають звіт власника, проби й ключ кеша (`міст_пакет._входи_пакета`).
    _короткий = bool((п.get("завдання") or {}).get("короткий_запис"))
    перелік = []
    for слот, рч in (п.get("пул") or {}).items():
        for r in (рч or []):
            о = річ(r, короткий=_короткий)
            if слот == "комплект":
                о["two_piece"] = True
            перелік.append(о)
    вих["pool"] = перелік
    # ШАПКА РОЗШИФРОВУЄ КОРОТКІ КЛЮЧІ — РАЗ НА ПАКЕТ, А НЕ НА КОЖНІЙ РЕЧІ (власник 27.09).
    # Лише про ключі, які в цьому пулі є (`легенда_ключів`), і лише в короткому записі: у
    # повному записі ключі повні, і шапці нема чого пояснювати.
    if _короткий:
        легенда = легенда_ключів(перелік)
        if легенда:
            вих["pool_keys"] = легенда
    о = п.get("обмеження") or {}
    if о.get("закріплені"):
        вих["her_items"] = list(о["закріплені"])
    вих.update(обмеження(о))
    # ТА САМА МЕЖА ДВІЧІ — РАЗ (ВМ-1): `she_refuses` (слова фільтра `жорстке_ні`) і
    # `case.refusals` (чинне вето паспорта) — один предикат (`міст_вхід._застосувати_паспорт`);
    # код, що вже стоїть у `case.refusals`, у `she_refuses` не повторюється.
    if вих.get("she_refuses") and isinstance((вих.get("case") or {}).get("refusals"), dict):
        _вже = {x for v in вих["case"]["refusals"].values() if isinstance(v, list) for x in v}
        _лишок = [x for x in вих["she_refuses"] if x not in _вже]
        if _лишок:
            вих["she_refuses"] = _лишок
        else:
            вих.pop("she_refuses")
    if о.get("пальто"):
        вих["coat_required"] = True
    # ── ПРАВИЛА СТИЛЮ — ЗАЯВАМИ ВНУТРІШНЬОЇ МОВИ (ВМ-1, CLAUDE.md п.12) ─────────────
    # Доти `style_rules` несли українські речення брифа (стенд, сід 3, «робочий день в
    # офісі»: 4 396 симв., 3 195 кириличних літер). Тепер кожен рядок брифа несе `заява`
    # (`brief.бриф`, ребра `hypergraph`, рядки схеми й бажань `міст_пакет`), і сюди їдуть
    # лише заяви — коди зі значеннями; що означає код, каже словник промпта
    # (`збирач_промптів.КЛЮЧІ_ЗАЯВ` → `statement_codes`). Однакова заява двох рядків — раз.
    # Рядки рівня нагоди (`формальність`, `ризик`, `маркери_щабля`, `K-KOH-08`) заяви ще не
    # мають — їх переробляє наряд НП-в, — і їдуть окремим `occasion_rules`, щоб перелік заяв
    # не мішав кодів із реченнями.
    if п.get("правила"):
        _заяви, _речення = [], []
        for x in п["правила"]:
            if isinstance(x, dict) and x.get("заява"):
                for з in заяви(x["заява"]):
                    if з not in _заяви:
                        _заяви.append(з)
            elif (x.get("рядок") if isinstance(x, dict) else x):
                _речення.append(x.get("рядок") if isinstance(x, dict) else x)
        if _заяви:
            вих["style_rules"] = _заяви
        if _речення:
            вих["occasion_rules"] = _речення
    if п.get("ноти_слотів"):
        # Ч-10 (рядок 223): нота слота — заяви, і вони стоять під ключем `statements`, бо
        # рівно його шукає збирач промптів (`збирач_промптів.КЛЮЧІ_ЗАЯВ`), щоб положити у
        # виклик словник визначень саме тих кодів, які цього разу приїхали.
        вих["kind_notes"] = {код("slot", с): {"statements": заяви(т)}
                             for с, т in п["ноти_слотів"].items() if т}
    if п.get("слоти_випали"):
        вих["kinds_missing"] = [код("slot", с) for с in п["слоти_випали"]]
    if isinstance(п.get("розрив"), dict) and п["розрив"].get("слот"):
        вих["break"] = {к: v for к, v in (("kind", код("slot", п["розрив"]["слот"])),
                                          ("why", п["розрив"].get("чому"))) if v}
    з = п.get("завдання") or {}
    if п.get("полюси"):
        вих["poles"] = полюси(п["полюси"], з.get("образів"))
    if п.get("полюси_недосяжні"):
        import протокол as _ПР
        # ЛИШЕ ID (ПР-10): «чому» — речення коду українською, а моделі досить знати, яких задумів
        # цей пул не дає; причина лишається в пакеті й у сліді K-VAR-01 для звіту власника.
        вих["poles_unavailable"] = [_ПР.ЗНАЧЕННЯ_ВІДПОВІДІ_EN["полюс"].get(x.get("ід"), x.get("ід"))
                                    for x in п["полюси_недосяжні"]]
    if п.get("реєстри_ід"):
        вих["register_rules"] = {реєстр(к): v for к, v in п["реєстри_ід"].items()}
    # КРАМНИЦІ («shops») У ПРОМПТ НЕ ЙДУТЬ (ПР-10): модель називає річ «n» повністю, і код
    # крамниці вже в ньому («#12·29»), тож «близнюк із тієї самої крамниці» видно без мапи; домени
    # нічого не додають до складання образу. Мапа лишається в пакеті (`магазини`) для людини.
    вих["outfits_wanted"] = int(з.get("образів") or 1)
    return вих
