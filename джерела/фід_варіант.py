# артикул «<модель з цифрою> <слово кольору>»: «2221 чорний», «10-325 шоколадний»,
# «2984 небесний з макадамія»; модель — лише латиниця, цифри й «-_./», щоб хвіст
# на кшталт «…-124487-Білий, голубка» (wearme) не читався моделлю з кольором
_АРТИКУЛ_ВАРІАНТА = re.compile(r"^([0-9A-Za-z._/\-]*\d[0-9A-Za-z._/\-]*)\s+(\D.*?)\s*$")
# `~колір` / `~color` / `~цвет`: сирий список кольорів товару, як його дає крамниця
_СПИСОК_ВАРІАНТІВ = ("~колір", "~color", "~цвет")


def _норм(т):
    """Слово для порівняння: нижній регістр, без пробілів по краях."""
    return str(т or "").strip().lower()


def _двоколірні_частини(поле):
    """Окремі слова двоколірного поля — або [], якщо хоч одне не є кольором."""
    частини = str(поле or "").split()
    return частини if len(частини) >= 2 and all(V.слово_крамниці(ч) for ч in частини) else []


def _слово_переліку(частина):
    """Лише колірні токени й модифікатори лексикону; речення опису — не кандидат.

    Дужки — службове уточнення фіду (мотив, відтінок), не текст для добору.
    Слова й модифікатори читає наявний лексикон, нового словника тут нема."""
    основа = re.sub(r"\([^()]*\)|\[[^\[\]]*\]", "", str(частина or ""))
    токени = re.findall(r"[\w'’]+", основа)
    if not токени or any(not (V.слово_крамниці(т) or _норм(т) in V._МОДИФІКАТОРИ_ПОЛЯ)
                         for т in токени):
        return None
    return V.слово_крамниці(частина)


def _вікно_слова(lab, слово):
    """Власне вікно слова й світлота модифікатора, без дозволу через сусіда сім'ї."""
    суд = V.перевірити(lab, ім=слово["ім"])
    return (суд["вердикт"] == "прийнято" and not суд.get("сусід_сім_ї")
            and _у_світлоті(lab, слово["ім"])
            and (not слово["мод"] or слово["вікно"][0] <= V.lch(lab)[0] <= слово["вікно"][1]))


def _підтон_слова(lab, слово, фото):
    """Перекриття вжитку не змінює тон на нейтраль чи навпаки.

    Сусідні назви одного роду можливі, коли підтон власної дуги слова
    не суперечить виміру; малу хрому не перетворюємо на іншу сім'ю
    без мінімальної хроми самого слова. Межі й дріж — з лексикону."""
    ім = слово["ім"]
    if V.сім_я_слова(ім) == V.сім_я_слова(фото):
        return True
    if V.слово_називає_тон(ім) != V.слово_називає_тон(фото):
        return False
    _, C, h = V.lch(lab)
    _, _, Cmin, _, дуга = V.ЛЕКСИКОН[ім]
    return C >= Cmin and (not дуга or V._тон_не_суперечить(h, дуга, C))


def поле_кольору_варіанта(o, зб, вар):
    """Єдине поле свідка для обох читачів; відкинутий перелік не судиться вдруге.

    Без артикула слово голови списку не є свідком цієї речі. Зберігаємо
    сирий перелік окремо, а далі передаємо тільки перевірені кандидати.
    Відсутність кандидата — відсутність слова, не новий колір крамниці."""
    if вар:
        return dict(o, колір_сирий=вар["слово"],
                    колір_назва=next(ч.strip() for ч in _СЕП_КОЛЬОРУ.split(вар["слово"]) if ч.strip()))
    список = список_варіантів(o)
    поле = o.get("колір_сирий") or o.get("колір_назва") or ""
    if not (зб and len(список) >= 2 and _норм(поле.split(",")[0]) == _норм(список[0])):
        return o
    фото, lab, _ = колір_збагачення(зб)
    слова = [ч for ч in список if (с := _слово_переліку(ч))
             and _вікно_слова(lab, с) and _підтон_слова(lab, с, фото)]
    return dict(o, колір_перелік_сирий=поле, колір_сирий=", ".join(слова),
                колір_назва=слова[0] if len(слова) == 1 else "")


def свідок_кольору_варіанта(o):
    """Відкинутий перелік не повертається через запасне читання назви товару."""
    return dict(o, назва="") if o.get("колір_перелік_сирий") and not o.get("колір_сирий") else o


def список_варіантів(o):
    """Частини `~колір` (або `~color`, `~цвет`) запису — або [], коли списку нема."""
    п = o.get("параметри") or {}
    сирий = next((п[к] for к in _СПИСОК_ВАРІАНТІВ if п.get(к)), "")
    return [ч.strip() for ч in str(сирий).split(",") if ч.strip()]


def артикул_варіанта(o):
    """(модель, слово) з артикула «2221 чорний» — або None, коли артикул іншої форми."""
    if not str(o.get("ключ_гілка") or "").startswith(("vendorCode", "article", "group_id")):
        return None
    м = _АРТИКУЛ_ВАРІАНТА.match(str(o.get("group_id") or "").split("@")[0])
    return (м.group(1), м.group(2)) if м else None


def сестри_варіантів(offers):
    """{(магазин, модель): {слова артикулів}} — скільки різних кольорів має модель у каталозі."""
    с = {}
    for o in offers:
        а = артикул_варіанта(o)
        if а:
            с.setdefault((o.get("магазин"), а[0]), set()).add(_норм(а[1]))
    return с


def слово_варіанта(o, зб, сестри):
    """dict(слово, поле, джерело, за_чим) — слово крамниці для ЦЬОГО запису, або None.

    `зб` — придатне збагачення запису (кадр не чужий) або None; `сестри` —
    `сестри_варіантів` усього каталогу. None — поле кольору лишається як є.
    Спершу слово варіанта моделі (кроки 1–3), потім слово назви з кадром (крок 4)."""
    return _слово_моделі(o, зб, сестри) or слово_назви_з_кадром(o, зб)


def _слово_моделі(o, зб, сестри):
    """Кроки 1–3 `слово_варіанта`: артикул, список варіантів, ряд кольорів моделі."""
    поле = o.get("колір_сирий") or o.get("колір_назва") or ""
    частини = [ч.strip() for ч in _СЕП_КОЛЬОРУ.split(поле) if ч.strip()]
    список = список_варіантів(o)
    кандидати = [(ч, с) for ч in список if (с := _слово_переліку(ч))]
    а = артикул_варіанта(o)
    # Жнива іноді склеюють два кольори моделі в `колір`, але лишають колір
    # цього варіанта окремо в сирому `~колір`. Беремо його лише коли воно
    # дослівно одне зі склеєних слів: тоді це свідок фіду, а не вгадування з тексту.
    два = _двоколірні_частини(поле)
    if len(список) == 1 and _норм(список[0]) in {_норм(ч) for ч in два}:
        return dict(слово=список[0], поле=поле, джерело="список варіантів",
                    за_чим="сирий ~колір «%s» — одне з %d слів поля"
                           % (список[0], len(два)))
    # артикул називає ВАРІАНТ, коли (а) в каталозі є сестри тієї ж моделі з іншим
    # кольором в артикулі, або (б) його колір є в списку кольорів моделі й це не
    # голова поля — тобто він не є тим першим кольором, яким складальник заповнив
    # поле («10-325 шоколадний» при полі «сірий, шоколадний», сестри «сірий» у
    # каталозі нема)
    if а:
        n = len(сестри.get((o.get("магазин"), а[0])) or ())
        у_списку = _норм(а[1]) in {_норм(ч) for ч in список} and _норм(а[1]) != _норм(поле.split(",")[0])
        if n >= 2 or у_списку:
            слово = а[1]
            if _норм(слово) == _норм(поле):
                return None
            if not (V.слово_крамниці(слово) or у_списку or _норм(слово) in {_норм(ч) for ч in список}):
                return None
            return dict(слово=слово, поле=поле or None, джерело="артикул варіанта",
                        за_чим="артикул «%s»: сторінка варіанта (%s); поле кольору — список кольорів моделі"
                               % (o.get("group_id", "").split("@")[0],
                                  "у каталозі %d кольорів моделі %s" % (n, а[0]) if n >= 2
                                  else "колір артикула є в списку моделі, але не першим"))
    # ряд кольорів моделі: список через кому, а без нього — повторені `~колір` (gepur)
    ряд = список if len(список) >= 2 else (o.get("кольори_ряду") or список)
    # голова поля порівнюється зі списком тим самим поділом, що й список (кома):
    # «Марсала/мигдаль, Світло-жовтий,» — перший варіант «Марсала/мигдаль», а не «Марсала»
    if len(ряд) < 2 or not частини or _норм(поле.split(",")[0]) != _норм(ряд[0]):
        return None
    перше = V.слово_крамниці(частини[0])
    # Фото судить лише список через кому. Повторені `~колір` — кольори з ВІДГУКІВ на
    # сторінці (gepur «Розмір S: співпадає розміру Колір: чорний», natalibolgar — відгуки
    # й на інші моделі): у них нема певності, що це варіанти саме цієї моделі, і сім'я
    # фото вибирала б чужий колір (ж-07266 «Спідниця міді синього кольору» → «Чорний»).
    if зб and ряд is список:
        # При малій хромі сім'я виміру не розрізняє блакитний і нейтраль.
        # Спершу звіряємо вікна слів САМОГО переліку; артикул і файл
        # розрізняють їх, коли вимір лежить одразу в кількох вікнах.
        фото, lab, _ = колір_збагачення(зб)
        # Широке вікно вжитку — необхідна умова, але не доказ підтону:
        # рожево-мавовий вимір не стає бежем, а аква — травою. Сім'я
        # самого виміру відокремлює такі перекриття без нового порога.
        придатні = [(ч, с) for ч, с in кандидати if _вікно_слова(lab, с)
                    and _підтон_слова(lab, с, фото)]
        файл = слово_файла(зб.get("фото"))
        # Одна сестра теж має свій артикул: коли його слово є в переліку
        # і тримає вимір, брак інших сестер не робить голову списку чужою.
        if а:
            for ч, с in кандидати:
                if (_норм(ч) == _норм(а[1]) and _вікно_слова(lab, с)
                        and (_підтон_слова(lab, с, фото)
                             or V.допуск_тону(V.lch(lab)[1]) == 180)):
                    return dict(слово=ч, поле=поле, джерело="варіант на фото",
                                за_чим="артикул у переліку; вимір кадру у вікні слова «%s»" % ч)
        свідки = ([("ім'я файла кадру «%s»" % файл["сире"], файл["ім"])] if файл else []) + \
                 [("фото картки — «%s»" % фото, фото)]
        for хто, слово in свідки:
            сім = V.сім_я_слова(слово)
            for ч, с in придатні:
                if V.сім_я_слова(с["ім"]) == сім:
                    if _норм(ч) == _норм(поле.split(",")[0]):
                        return None
                    return dict(слово=ч, поле=поле, джерело="варіант на фото",
                                за_чим="%s; вимір кадру у вікні слова переліку «%s»" % (хто, ч))
        if len(придатні) == 1:
            ч = придатні[0][0]
            return dict(слово=ч, поле=поле, джерело="варіант на фото",
                        за_чим="єдине слово переліку у вікні виміру кадру — «%s»" % ч)
        # Нема слова того ж підтону у власному вікні — вибору нема;
        # резервний свідок сім'ї не може обійти ці умови через назву.
        return None
    # Слово кольору в НАЗВІ цієї пропозиції — свідок крамниці про неї саму, коли воно є
    # в ряду не головою (той самий ключ лексикону): два слова крамниці згодні, який колір
    # продається за цим посиланням (рядок 4688). Для списку через кому — лише коли фото
    # не розсудило. Береться слово ряду як його читає лексикон (`назва`: «: Бордовий» →
    # «бордовий»), без нового словника.
    ім_назви = V.назва_кольору(o.get("назва") or "")
    if ім_назви and not (перше and перше["ім"] == ім_назви):
        for ч in ряд[1:]:
            с = _слово_переліку(ч)
            if с and с["ім"] == ім_назви:
                return dict(слово=с["назва"], поле=поле, джерело="варіант у назві",
                            за_чим="товар із %d кольорами в ряду (%s); слово назви — «%s» ряду"
                                   % (len(ряд), ", ".join(ряд), ч))
    return None


# Слова назви для `V.слово_крамниці`: дефіс лишається в слові («світло-коричневий» — слово
# крамниці з модифікатором), а для переліку кольорів назви дефіс — межа («чорно-білі»).
_МЕЖА_СЛОВА = re.compile(r"[^\w'’-]+")
_МЕЖА_КОЛЬОРУ = re.compile(r"[^\w'’]+")


def _у_світлоті(lab, ім):
    """Світлота `lab` у межах вікна вжитку САМОГО слова `ім` (`V.вікно_вжитку`), без сусідів сім'ї."""
    Lmin, Lmax = V.вікно_вжитку(ім)[:2]
    return Lmin <= V.lch(lab)[0] <= Lmax


def слово_назви_з_кадром(o, зб):
    """Крок 4 (рядок 4751): dict як у `слово_варіанта` — слово кольору НАЗВИ, коли поле кольору
    суперечить і їй, і виміру кадру жнив, а назва з кадром згодні (п.18); інакше None.

    Діє лише там, де без нього колір лишився б за полем: вимір у спорі з полем (`колір_спір`),
    який не переважили кадри галереї (крок 2 `фід_кадр_колір.після_спору`), або у вікні вжитку
    слова поля (`фід_збагачення._назва_кольору` тоді лишає слово поля).
      · поле суперечить кадру — сім'я тону виміру (те, що вимір каже сам) не сім'я жодного
        слова поля;
      · назва з кадром згодні — вимір у вікні вжитку слова назви (`V.перевірити`), і його
        світлота — у вікні самого слова: `перевірити` приймає й вікна сусідів сім'ї, а
        «капучино» — ключ «графіт» (L* 2–56), і світла сумка, виміряна «срібним» (L* 72), —
        не графіт (ж-08158); коли назва називає кілька кольорів — ще й у сім'ї слова назви;
      · річ на кадрі двоколірна (`колір_другий`) — поле лишається (п.18: двоколірні лишають
        вікно слова): ж-09572 — замша «капучино», а головним виміряно темну підошву;
      · назва, що називає й колір поля («СВІТЛА ОЛИВА + АЙВОРІ» при полі «Світла оливка»,
        «чорно-білі» при «білий»), — не свідок проти поля;
      · близьке слово — центр вікна слова поля у вікні вжитку слова назви («білий» при
        «молочний»): поле вже каже колір назви.
    Слово назви — ключ `V.назва_кольору`; у запис іде те слово назви, яке написала крамниця
    («світло-коричневий», «капучино»), коли `V.слово_крамниці` читає його тим самим ключем, —
    інакше сам ключ."""
    # назва фіду, що не пройшла суд назви (`назва_речі`: речення опису, розділ, бренд — тоді
    # картка показує іншу назву), — не свідок кольору речі: «…оброблена бейкою чорного
    # кольору…» (ж-00432@morandi, сіро-синій сарафан), «…поєднується з молочними…» (ж-01778)
    if o.get("назва_показу_джерело") not in (None, "фід"):
        return None
    поле = o.get("колір_сирий") or o.get("колір_назва") or ""
    слова = [с["ім"] for с in map(V.слово_крамниці, _СЕП_КОЛЬОРУ.split(поле)) if с]
    назва = o.get("назва") or ""
    ім = V.назва_кольору(назва)
    if not (зб and слова and ім):
        return None
    у_назві = {ім} | {с["ім"] for с in map(V.слово_крамниці, _МЕЖА_КОЛЬОРУ.split(назва)) if с}
    фото, lab, _ = колір_збагачення(зб)
    сім = V.сім_я_слова(фото)
    сім_поля = {V.сім_я_слова(с) for с in слова}
    прийнято = lambda lab_, с: V.перевірити(lab_, ім=с)["вердикт"] == "прийнято"
    if (сім is None or зб.get("колір_другий") or у_назві & set(слова) or сім in сім_поля
            or not (прийнято(lab, ім) and _у_світлоті(lab, ім))
            or (len(у_назві) > 1 and сім != V.сім_я_слова(ім))
            or any(прийнято(_центр_вікна(V.ЛЕКСИКОН[с]), ім) for с in слова if с in V.ЛЕКСИКОН)):
        return None
    спір = колір_спір(зб, o)
    if not (спір or any(прийнято(lab, с) for с in слова)):
        return None
    if спір:
        # кадри галереї згодні проти поля (крок 2 `після_спору`) — колір і так з фото
        # (ж-09677: три кадри «графіт» проти «бежевий»); імпорт тут, бо `фід_кадр_колір`
        # імпортує цей модуль. Контекст — лише виміри кадрів: крок 1 тут не потрібен.
        from фід_кадр_колір import після_спору, читати_кадри
        if після_спору(o, зб, спір, dict(кадри=читати_кадри(), спільні={}, рівні_папок={}))["позначка"]:
            return None
    слово = next((с["назва"] for с in map(V.слово_крамниці, _МЕЖА_СЛОВА.split(назва))
                  if с and с["ім"] == ім), ім)
    return dict(слово=слово, поле=поле, джерело="слово назви з кадром",
                за_чим="поле «%s» суперечить і назві, і кадру («%s»); слово назви «%s»" % (поле, фото, слово))


def слово_файла(url):
    """dict(ім, сире) — перше слово кольору в імені файла кадру («…_navy_5-824x1236.webp») або None.

    Ім'я файла дає крамниця, тож це її слово про САМЕ ЦЕЙ кадр; читається лише
    цілими частинами між «_», «-», «.» — як латиниця поля кольору (`V.слово_крамниці`)."""
    ім_файла = str(url or "").split("?")[0].rsplit("/", 1)[-1].lower()
    for частина in re.split(r"[_\-.\s]+", ім_файла):
        с = V.слово_крамниці(частина) if re.fullmatch(r"[a-z]{3,}", частина) else None
        if с:
            return dict(ім=с["ім"], сире=частина)
    return None
