"""фід_варіант.py — чиє слово кольору стоїть у записі: сторінки ВАРІАНТА чи ТОВАРУ з кількома варіантами (рядок 142).

ЩО ТУТ БУЛО (вимір куратора 23.09.2026 і виконавця того ж дня, каталог_повний,
main 44bc13f). Зі 5 034 спорів кольору в 2 565 сім'я слова з фото ≠ сім'ї слова
крамниці, і за правилом §5 код брав слово крамниці. Але «слово крамниці» тут —
ПЕРША частина поля «Колір», а в трьох крамницях це поле — не колір запису:
складальник каталогу клав у нього голову списку ВСІХ кольорів моделі, обрізану до
двох і з комою в кінці («бежевий, кемел,» при `~Колір` «бежевий, кемел, сірий,
чорний»). Кома стоїть рівно там, де список довший за поле: sunwin 476 записів,
wearme 262, maxa 165, rito 4, vmma 3 (звірено по всьому XML — жодного винятку).
Два механізми, звірені на сторінках крамниць:
  (1) ЗАПИС — СТОРІНКА ВАРІАНТА (sunwin): у кожного кольору своя сторінка
      (`…-2221bc/`), свій артикул «2221 чорний» і свої фото `2221.6540_*.webp`;
      поле кольору — голова списку сестринських сторінок. ж-00047: артикул
      «2221 чорний», фото чорне, поле «бежевий, кемел» → код казав «бежевий».
  (2) ЗАПИС — ТОВАР З УСІМА ВАРІАНТАМИ (maxa, wearme): одна сторінка, вибір
      кольору на ній, галерея з кадрами різних варіантів; фото картки — один із
      них. ж-02157 maxa: варіанти «Марсала/мигдаль, Світло-жовтий, Світло-
      жовтий/мигдаль», фото жовте → код казав «марсала».
ЩО СТАЛО. Слово крамниці для запису вибирається серед слів САМОЇ крамниці про ЦЕЙ
запис, до суду `колір_спір`, і саме правило §5 не міняється:
  (1) артикул «<модель> <колір>», коли в каталозі тієї ж крамниці є сестри тієї
      самої моделі з ІНШИМ кольором в артикулі (доказ, що артикул називає
      варіант, а не товар), — слово артикула стає полем кольору запису;
  (2) товар без такого артикула, чиє поле кольору — голова списку `~колір` із ≥ 2
      варіантів: слово списку тієї ж сім'ї тону, що й фото картки, стає полем
      кольору — крамниця продає цей колір за цим посиланням, і саме його жінка
      бачить на фото. Нема слова тієї сім'ї — поле лишається як було, і далі все
      як доти (спір, позначка).
Згода чи спір із фото й поріг згоди далі судить `колір_спір` рівно як доти — тепер
проти слова варіанта, а не проти голови чужого списку. Нового гейта нема: запис
не відсівається й не додається, міняється лише те, яке слово крамниці є свідком.
Старе поле лишається в записі (`колір_варіант["поле"]`) з названою причиною.
"""
import re
import verify as V
from фід_розбір import _СЕП_КОЛЬОРУ
from фід_збагачення import колір_збагачення

# артикул «<модель з цифрою> <слово кольору>»: «2221 чорний», «2984 небесний з макадамія»
_АРТИКУЛ_ВАРІАНТА = re.compile(r"^(\S*\d\S*)\s+(\D.*?)\s*$")
# `~колір` / `~color` / `~цвет`: сирий список кольорів товару, як його дає крамниця
_СПИСОК_ВАРІАНТІВ = ("~колір", "~color", "~цвет")


def _норм(т):
    """Слово для порівняння: нижній регістр, без пробілів по краях."""
    return str(т or "").strip().lower()


def список_варіантів(o):
    """Частини `~колір` (або `~color`, `~цвет`) запису — або [], коли списку нема."""
    п = o.get("параметри") or {}
    сирий = next((п[к] for к in _СПИСОК_ВАРІАНТІВ if п.get(к)), "")
    return [ч.strip() for ч in str(сирий).split(",") if ч.strip()]


def артикул_варіанта(o):
    """(модель, слово) з артикула «2221 чорний» — або None, коли артикул іншої форми."""
    if not str(o.get("ключ_гілка") or "").startswith(("vendorCode", "article", "group_id")):
        return None
    м = _АРТИКУЛ_ВАРІАНТА.match(str(o.get("group_id") or "").split("@")[0])
    return (м.group(1), м.group(2)) if м else None


def сестри_варіантів(offers):
    """{(магазин, модель): {слова артикулів}} — скільки різних кольорів має модель у каталозі."""
    с = {}
    for o in offers:
        а = артикул_варіанта(o)
        if а:
            с.setdefault((o.get("магазин"), а[0]), set()).add(_норм(а[1]))
    return с


def слово_варіанта(o, зб, сестри):
    """dict(слово, поле, джерело, за_чим) — слово крамниці для ЦЬОГО запису, або None.

    `зб` — придатне збагачення запису (кадр не чужий) або None; `сестри` —
    `сестри_варіантів` усього каталогу. None — поле кольору лишається як є."""
    поле = o.get("колір_сирий") or o.get("колір_назва") or ""
    частини = [ч.strip() for ч in _СЕП_КОЛЬОРУ.split(поле) if ч.strip()]
    список = список_варіантів(o)
    а = артикул_варіанта(o)
    if а and len(сестри.get((o.get("магазин"), а[0])) or ()) >= 2:
        слово = а[1]
        if _норм(слово) == _норм(поле):
            return None
        if not (V.слово_крамниці(слово) or _норм(слово) in {_норм(ч) for ч in список}):
            return None
        return dict(слово=слово, поле=поле or None, джерело="артикул варіанта",
                    за_чим="артикул «%s»: сторінка варіанта (у каталозі %d кольорів моделі %s); "
                           "поле кольору — список сестринських сторінок"
                           % (o.get("group_id", "").split("@")[0], len(сестри[(o.get("магазин"), а[0])]), а[0]))
    if not зб or len(список) < 2 or not частини or _норм(частини[0]) != _норм(список[0]):
        return None
    # хто каже, який варіант на фото: спершу ім'я файла кадру (слово самої
    # крамниці: `CB000003488_pink_1.jpg`), потім слово моделі з того самого кадру
    файл = слово_файла(зб.get("фото"))
    свідки = ([("ім'я файла кадру «%s»" % файл["сире"], файл["ім"])] if файл else []) + \
             [("фото картки — «%s»" % колір_збагачення(зб)[0], колір_збагачення(зб)[0])]
    перше = V.слово_крамниці(частини[0])
    for хто, слово in свідки:
        сім = V.сім_я_слова(слово)
        if перше and V.сім_я_слова(перше["ім"]) == сім:
            return None
        for ч in список:
            с = V.слово_крамниці(ч)
            if с and V.сім_я_слова(с["ім"]) == сім:
                return dict(слово=ч, поле=поле, джерело="варіант на фото",
                            за_чим="товар із %d варіантами (%s); %s, слово крамниці тієї ж сім'ї тону"
                                   % (len(список), ", ".join(список), хто))
    return None


def слово_файла(url):
    """dict(ім, сире) — перше слово кольору в імені файла кадру («…_navy_5-824x1236.webp») або None.

    Ім'я файла дає крамниця, тож це її слово про САМЕ ЦЕЙ кадр; читається лише
    цілими частинами між «_», «-», «.» — як латиниця поля кольору (`V.слово_крамниці`)."""
    ім_файла = str(url or "").split("?")[0].rsplit("/", 1)[-1].lower()
    for частина in re.split(r"[_\-.\s]+", ім_файла):
        с = V.слово_крамниці(частина) if re.fullmatch(r"[a-z]{3,}", частина) else None
        if с:
            return dict(ім=с["ім"], сире=частина)
    return None
