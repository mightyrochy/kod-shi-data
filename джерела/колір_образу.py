def _lab(x):
    return hx(x) if isinstance(x, str) else tuple(x)

def гучність(lab):
    """Наскільки колір «голосний». Абсолютна C*, не відносна.
    ЧОМУ не rel_C (як у colorspace для рис обличчя): гамут звужується на темних
    світлотах, тому нейві дає rel_C=0.58, а денім 0.52 — і обидва хибно ставали б
    «високонасиченими елементами» бюджету K-COL-02, хоча корпус прямо називає їх
    нейтралями. rel_C лишається правильним для дуг спектра рис; для гучності — ні."""
    L, Cc, h = lch(lab)
    cm = c_max(L, h)
    return dict(L=round(L,1), C=round(Cc,1), h=round(h,1),
                rel_C=round(Cc/cm, 2) if cm > 1e-6 else 0.0,
                гучний=Cc >= C["hi_C"])

def нейтраль(lab):
    """K-COL-06. Нейтраль — не «сірий», а членство в одній із двох сімей.
    Де ламається: межі коридорів — конвенція корпусу, не вимір; бордо (C=37,h=16°)
    навмисно лишається кольором, хоч і приглушеним."""
    L, Cc, h = lch(lab)
    if Cc < C["neutral_C"]:
        return ("тепла" if lab[2] > C["b_нейтралі"][0] else
                ("холодна" if lab[2] < C["b_нейтралі"][1] else "ахроматична"))
    _ε = 1e-9   # atan2/hypot повертають 44.999…996 на куті, СКОНСТРУЙОВАНОМУ як 45.0:
    # без допуску вікно, що ділить межу з коридором, падає крізь неї (спіймано
    # гейтом §12 check_edits на «молочний», кут h=45). Це чисельність, не правило.
    lo, hi, cmax = C["warm_neutral"]
    if lo - _ε <= h <= hi + _ε and Cc <= cmax + _ε: return "тепла"
    lo, hi, cmax = C["cool_neutral"]
    # темні холодні (нейві-зона): стеля хроми вища — див. історію в REGISTRY["cool_neutral"].
    # Числа T3; перевірено лише на те, що не ламає гейти (roundtrip), НЕ на фіді.
    if L <= 45.0 and Cc <= 34.0: cmax = 34.0
    if lo - _ε <= h <= hi + _ε and Cc <= cmax + _ε: return "холодна"
    return None

# Межі ВИМІРЯНІ на якорях у цьому ж просторі, не взяті з колірного кола:
