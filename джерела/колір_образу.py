# ── ОДНА ПОЛІТИКА НА НЕВИМІРЯНУ ПЛОЩУ: УТРИМУЄТЬСЯ (Н-outfit-1-084) ──────────
# `елементи()` прямо каже: «area = r.get("площа") — None = не виміряно; не
