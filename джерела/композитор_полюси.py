def _вигляд_виміру(F, по_слотах, тіло, слоти, скільки, сід, жорстке_ні, вето, kw):
    """Той самий ВИГЛЯД, що композитор давав до 31.08 — але над ВИБІРКОЮ.

    ЩО ЦЕ І ЧИМ НЕ Є. Тести читали з `зібрати()` не лише `_оцінені`, а й похідні
    від них числа: `перебрано`, `чистих`, `граф` і `вузол_напруги` найкращої
    комбінації, `портфель`. Питання, які вони ставлять, живі — «чи правило хоч раз
    спрацювало на речах із фіду», «чи граф має ребро K-INT-04». Померло лише те,
    що код САМ обирав переможця й показував його моделі.

    Тому вигляд відновлено тут, за прапорцем `вимір=N`, і рахується він над
    вибіркою з `вимір_правил`, а не над декартовим добутком: пам'ять не залежить
    від кількості слотів. `bridge` цього прапорця не передає ніколи.
    """
    оцінені, викинуто_дублів = _образи_для_виміру(
        F, по_слотах, тіло, скільки=скільки, сід=(сід or 42),
        жорстке_ні=жорстке_ні, вето=вето, **kw)
    if not оцінені:
        return dict(_оцінені=[], перебрано=0, чистих=0,
                    вибірка=dict(скільки=0, викинуто_дублів=викинуто_дублів))
    # ── ВИБІРКА ВІДДАЄТЬСЯ ВПОРЯДКОВАНОЮ, А НЕ В ПОРЯДКУ ЖЕРЕБА ──────────────
    # Композитор сортував `_оцінені` за ключем, і тести читають саме ПОРЯДОК:
    # «при +14 тренч вище за пуховик, при −5 — нижче» — це і є розрізнювальна
    # здатність правила. Перша версія виміру віддавала образи в порядку вибірки,
    # тож ранг був жеребом і правило виглядало мертвим. Сортування те саме:
    # спершу без блокерів, далі за сумою сил; id — щоб нічиї не гуляли між
    # прогонами.
    # ── K-P0-01 ПЕРЕЇХАВ ІЗ КОМЕНТАРЯ В КЛЮЧ (17.09.2026) ────────────────────
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ. Блок у `_оцінити` вже носить заголовок «ПОСАДКА —
    # ГЕЙТ, НЕ КРИТЕРІЙ З ВАГОЮ» і дослівно обіцяє: «між двома блокованими блок
    # посадки важить першим (ключ сортування нижче)». Ключ нижче цього не робив:
    # він брав `x["блокує"]` — ЛІЧБУ блокерів будь-якого роду, — тож комбінація з
    # ОДНИМ блоком посадки ставала попереду комбінації з ДВОМА композиційними,
    # тобто «не сидить» вигравало в «сидить, але два зауваження». Це і є
    # «зважений критерій», який правило називає помилкою; посадка важила рівно
    # стільки, скільки будь-яка інша знахідка, і корпусне `strong` на архітектурі
    # жило коментарем. Число `_блок_посадки` рахувалось у `_оцінити` й лежало в
    # кожному рядку `оцінені` — і не читав його НІХТО.
    # after: перший ключ — «посадка блокує?», і лише потім лічба решти блоків та
    # сума сил. Комбінація, яка не сидить, не обходить жодну, яка сидить.
    # МЕЖА, НАЗВАНА ПРЯМО: гейт спрацьовує лише там, де посадку взагалі є з чого
    # порахувати. На живому каталозі `верх_см/низ_см` беруть із ДЕФОЛТУ СЛОТА
    # (фід не несе мірок виробу), і тоді шар посадки нічого не блокує — виміряно
    # на `каталог_повний.xml`: 12 образів, блокерів посадки 0. Тобто правило тепер
    # правильне й мовчазне; оживить його не правка тут, а мірки виробу у фіді.
    оцінені.sort(key=_ключ_ранжування)
    найкраще = оцінені[0]
    г = найкраще["граф"]
    вузол = ГР.вузол_напруги(г)
    _розр_вим, _резон_вим = ГР.розрізнювальні(оцінені)[:2]
    живі = [с for с in слоти if по_слотах.get(с)]
    return dict(
        _оцінені=оцінені,
        перебрано=len(оцінені),
        чистих=sum(1 for x in оцінені if not x["блокує"]),
        самоперетинів=0,
        граф=г, вузол_напруги=вузол,
        образ=[dict(id=r.get("id"), назва=r.get("назва"), слот=r.get("слот"),
                    ціна=r.get("ціна"), тип=r.get("тип"),
                    відстань_до_центру=r.get("_відстань"))
               for r in найкраще["речі"]],
        знахідки=найкраще["знахідки"], блокери=найкраще["блокери"],
        портфель=_портфель(оцінені, найкраще, вузол=вузол),
        вибірка=dict(спосіб="рівномірна вибірка з пулу (вимір_правил), не добуток",
                     скільки=len(оцінені), викинуто_дублів=викинуто_дублів),
        # ОЗНАЧЕННЯ БЕРЕТЬСЯ З `graph`, А НЕ ВИГАДУЄТЬСЯ ТУТ. Перша версія рахувала
        # резонансні як «правило є в УСІХ образах» — і K-CUT-00 випадав, бо
        # спрацьовує не скрізь. Канонічне означення тонше: резонансне те, чия
        # НАПРУГА не різниться між комбінаціями, тобто воно не впорядковує пул.
        резонансні=sorted(_резон_вим), розрізнювальні=sorted(_розр_вим),
        чому_цей=_пояснити(найкраще, {}, вузол=вузол, резон=_резон_вим),
        координація=_координація_з(оцінені, найкраще),
        _речі=найкраще["речі"], _вихід=найкраще.get("вихід"))


# ── ЧОМУ ГІЛКА `вимір=N` ЛИШИЛАСЬ (Н-02-03, С-62, 13.09.2026) ────────────────
# Наряд назвав `_портфель` під `вимір=N` кандидатом на знесення (V31). Правило
# наряду — «є виклик із продукту, тесту чи приладу — лишити», — і вимір каже
