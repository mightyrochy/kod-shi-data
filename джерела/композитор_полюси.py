#   · `measure_coordination.py:62`  — `КМ.зібрати(..., вимір=200)`, далі читає
#     `вершина_змінилась` і `чи_розрізняє` з `_координація_з` (:76–77);
#   · `run_outfit.py:210–212`       — `КМ.зібрати(..., вимір=200)`, далі читає
