def роль_принту(палітра, слоти, слот_принту, _intent="conventional",
                нейтраль_як_колір=False):
    """Напрям A. Принтована річ у слоті `слот_принту` несе КІЛЬКА кольорів
    (вихід feed.палітра_принту). Рішення, яке це змінює:
      before — принт читається одним домінантним кольором, інші слоти йдуть у матч
               домінанти, власні секундант/акцент принту ігноруються;
      after  — домінанта+секундант принту закривають свої РОЛІ, а сольний слот
               дістає запит на АКЦЕНТ, що ПОВТОРЮЄ колір із принту (Тайх/Штольцфус:
               «повтори колір, який уже є у візерунку»).

    ЖОДНИХ СУВОРИХ ЗАБОРОН. Гучність принту (feed._гучність_принту — самовідносна
    сила властивості, не поріг) НЕПЕРЕРВНО модулює три речі:
      • сила ехо (`сила_ехо` = 1−гучність, з підлогою 0.15 — ехо ніколи не
        вимикається обривом): тихий принт → ехо сильне, може лягти на гарнітур;
        гучний → ехо слабке й стримане (Boutorabi: «low-key OR one echo»);
      • стеля хроми ехо: тихо → яскраве, гучно → приглушеніше (Lamport: гучний
        принт «дате you», тримай супровід тихішим);
      • `нейтраль_перевага` = гучність: що гучніший принт, то сильніший сигнал
        «решту слотів у нейтраль, дай оку відпочити» (майже одностайно в джерелах).
    Носій ехо тяжіє до дрібного (сумка/взуття/пояс/шарф), бо джерела кладуть ехо
    гучного принту саме в аксесуар (nolishop: пояс; mariapersonalshopper: сумка/взуття).

    Тон солідів — не членство в дузі, а ТЯЖІННЯ (`тяжіння_тону`): центри = кольори
    принту, сила спадає з тон-відстанню (feed.відстань_до_вікна дає градієнт);
    компліментарний тон не заборонений, лише слабший («similar, not exact»;
    «contrast, not matching»). Вікно ехо лишається обмеженим — це механізм ВИБІРКИ
    з каталогу, не заборона образу; рішення несе поле `сила`.

    Розвилка практиків (нейтраль принту = колір?): дефолт — ні (нейтралі = `нитки`,
    дозволені як солід, роль не займають); нейтраль_як_колір=True вмикає інше.
    Масштаб/рух/чіткість-краю принту НЕ вимірюються (color-only; з 5 компонент Raes
    доступні лише контраст і груба щільність — див. feed._гучність_принту).

    `_intent` НЕ ЧИТАЄТЬСЯ СВІДОМО: сила ехо, стеля хроми й `нейтраль_перевага` йдуть
    з ГУЧНОСТІ принту (самовідносна властивість речі), і жодне джерело напряму A не
    в'яже їх із наміром; хвіст сигнатури лишається як у решти входів палітри."""
    АКСЕСУАРИ = ("сумка", "взуття", "пояс", "шарф", "прикраси", "головний_убір")
    ролі = list(палітра.get("ролі", []))
    нитки = list(палітра.get("нитки", []))
    гучність = float(палітра.get("гучність", 0.0))
    if нейтраль_як_колір and нитки:
        ролі = ролі + [dict(нитки[0], роль="секундант")]
    закриває = [r["роль"] for r in ролі]
    інші = [s for s in слоти if s != слот_принту]
    ехо = min(ролі, key=lambda r: r["частка"]) if ролі else None

    сила_ехо = round(max(0.15, 1.0 - гучність), 2)     # неперервна, з підлогою (ніколи 0)
    запит_ехо = None
    if ехо and інші:
        # носій ехо: якщо є аксесуарний слот — туди (безпечний носій повтору),
        # інакше акцентний за дефолтом, інакше останній зі слотів
        аксес = [s for s in інші if s in АКСЕСУАРИ]
        цільовий = (min(аксес, key=lambda s: АКСЕСУАРИ.index(s)) if аксес
                    else next((s for s in інші if ДЕФОЛТ_РОЛЕЙ.get(s) == "акцент"), інші[-1]))
        L, h = ехо["L"], ехо["h"]
        a, b = _дуга(h, 18.0)                           # T3 дуга ехо
        # стеля хроми ехо неперервно падає з гучністю: тихо → яскраве, гучно → стриманіше
        C_стеля = round(ПРИГЛУШЕНО[1] + (1.0 - гучність) * ((ГУЧНО + 8.0) - ПРИГЛУШЕНО[1]), 1)
        запит_ехо = dict(слот=цільовий,
                         L_min=round(max(0, L-12), 1), L_max=round(min(100, L+12), 1),
                         C_min=ПРИГЛУШЕНО[0], C_max=C_стеля,
                         h_from=a, h_to=b, нейтраль=False, роль="ехо-акцент",
                         сила=сила_ехо,
                         джерело="повтор кольору принту h≈%d (сила %.2f)" % (round(h), сила_ехо))
    тяжіння_тону = [dict(h=round(r["h"], 1), сила=1.0) for r in ролі]   # центри, сила спадає з відстанню
    return dict(
        закриває=закриває, запит_ехо=запит_ехо,
        нейтраль_перевага=round(гучність, 2),           # неперервна сила сигналу «решта в нейтраль»
        тяжіння_тону=тяжіння_тону,
        нитки_дозволені=[n["lab"] for n in нитки],
        гучність=round(гучність, 2),
        нота="принт закриває %d рол(і); ехо сила=%.2f → %s; нейтраль-перевага=%.2f" % (
            len(закриває), сила_ехо,
            (запит_ехо["слот"] if запит_ехо else "нема куди"), гучність))


