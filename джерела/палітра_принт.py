def _кат(сила_нп):
    """Неперервна сила -> категорія лише для сумісності з форматом знахідок outfit.
    Стеля «soft»: усі правила цього блоку — T3 некалібровані конвенції, тому
    «hard»/«strong» недосяжні за конструкцією (сила ≤ верифікація)."""
    return "soft" if сила_нп >= _РЕЄСТР.C["нп_межа_soft"] else "hint"


def принт_придатність(палітра, F=None, source="protocolized", масштаб_особи=None,
                      рух=None, риси_рух=None, зона_камуфляж=None, слот_принту=None,
                      надійність_масштабу=None, річ_ім=None, річ_ід=None):
    """Правила практиків про придатність принту ОСОБІ, як компільовані блоки.
    Жодних заборон: кожна знахідка несе неперервну `сила_нп` ∈ [0,1] і йде через
    реєстр_правил._зн, де невідомі правила дефолтять у «репліку» (не блокує).

    Живі сьогодні (вхід виміряний):
      P-PRT-02  чіткість краю ↔ контраст особи (Raes: чіткий край просить
                визначених рис/контрасту; washy — м'яких).
      P-PRT-05  див. `мікс_принтів` — різниця масштабів двох принтів.
    Частково живі: P-PRT-01 (масштаб принту виміряний, масштаб особи — ні).
    Інертні до появи виміру: P-PRT-03 (камуфляж), P-PRT-04 (рух).

    Ефективний масштаб (Lamport): високий контраст робить принт «більшим» на око,
    тому масштаб множиться на (1 + 0.5·контраст_норм) — це вимірюваний множник,
    не здогадка."""
    зн, нема_виміру = [], []
    м = палітра.get("масштаб_відн"); чк = палітра.get("чіткість_краю")
    ґр = палітра.get("ґрунт");       кп = палітра.get("контраст")
    # ── ТРИ РІЗНІ ПОНЯТТЯ, ЯКІ ЇХАЛИ В ОДНОМУ ПАРАМЕТРІ (Н-palette-2-102) ─────
    # `слот_принту` називався слотом, а приходив у нього SKU (outfit передавав
    # r["id"]). P-PRT-03 звіряв його з `зона_камуфляж`, яку діалог дає НАЗВОЮ
    # СЛОТА, тож рівність не виконувалась ніколи і правило зникало мовчки — не
    # потрапляючи навіть у `нема_виміру`. Тепер поняття розведені явно:
    #   слот_принту — СЛОТ (з чим звіряється зона камуфляжу),
    #   річ_ім      — назва для ТЕКСТУ («блуза у горох»),
    #   річ_ід      — ідентифікатор для списку `речі` (те, що кладуть усі інші
    #                 правила: пор. outfit `[ведучий["річ"]]`).
    річ = річ_ім or слот_принту or "принтована річ"
    ід = річ_ід or річ_ім or слот_принту or "принтована річ"

    # ── P-PRT-01: масштаб принту ↔ масштаб особи ────────────────────────────────
    if м is None:
        нема_виміру.append(dict(правило="P-PRT-01", бракує="масштаб_відн",
                                причина="однотонна річ або принт не розпізнано"))
    elif масштаб_особи is None:
        нема_виміру.append(dict(правило="P-PRT-01", бракує="масштаб_особи",
                                потрібно=КОНТРАКТ_ПРИНТУ["масштаб_особи"]["потрібно"],
                                маємо=dict(масштаб_відн=м, ефективний=round(
                                    м*(1+0.5*min(1.0, (кп or 0)/55.0)), 3))))
    else:
        еф = min(1.0, м*(1 + 0.5*min(1.0, (кп or 0)/55.0)))
        norm = min(1.0, еф/0.30)                       # T3: 0.30 кадру -> «великий»
        розрив = abs(norm - масштаб_особи)
        сила_нп = round(min(1.0, розрив/1.0), 2)       # T3: повна сила лише при
                                                       # максимальному розриві
        if сила_нп >= _РЕЄСТР.C["нп_підлога"]:
            бік = "дрібнішим" if norm > масштаб_особи else "більшим"
            # ── ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026) ───────────
            # НАПРЯМ БУВ ПОРАХОВАНИЙ І НЕ ДОЇЖДЖАВ. `бік` рахується рядком вище
            # й живе далі ЛИШЕ в `ремонт`, а `ремонт` до моделі не доходить:
            # `bridge._стислі_знахідки` лишає (правило, сила, сила_нп, суть,
            # речі), `pipeline.промпт_ремонту` друкує саму `суть` із числом, і
            # на виході `суд_образу.для_стиліста` ключа `ремонт` у знахідці вже
            # немає взагалі. Зміряно синтетичним прогоном крізь
            # `pipeline.перевірити_образ` (див. рядок так, як його друкує промпт):
            #   before, мотив 0.42 на особі 0.15 (треба ДРІБНІШИЙ):
            #     · масштаб мотиву не в масштабі особи [0.85]
            #   before, мотив 0.04 на особі 0.90 (треба БІЛЬШИЙ):
            #     · масштаб мотиву не в масштабі особи [0.75]
            # Два протилежні ремонти — один рядок: старий текст називає ВІСЬ
            # («не в масштабі») і мовчить про бік, тож вибір між дрібнішим і
            # більшим мотивом лишався монеткою.
            #   after, той самий прогін, ті самі сили:
            #     · «блуза у великий горох»: мотив не в масштабі особи —
            #       узяти принт з дрібнішим мотивом [0.85]
            #     · «сорочка в дрібну квітку»: мотив не в масштабі особи —
            #       узяти принт з більшим мотивом [0.75]
            # Бік НЕ рахується заново: у реченні стоїть той самий `бік`, що вже
            # порахований рядком вище для `ремонт`; жодного числа в тексті нема.
            зн.append(dict(_РЕЄСТР._зн("P-PRT-01", _кат(сила_нп),
                "«%s»: мотив не в масштабі особи — узяти принт з %s мотивом"
                % (річ, бік), [ід],
                "виміряний масштаб %.2f (ефективний %.2f з поправкою на контраст) проти "
                "масштабу особи %.2f" % (м, еф, масштаб_особи),
                ремонт="узяти принт з %s мотивом" % бік,
                примітка=(None if надійність_масштабу is None else
                          "надійність входу масштабу %.2f (зріст зі самозвіту занижує "
                          "надійність, але НЕ силу — це різні осі)" % надійність_масштабу),
                ламається="правило родом з одного родоводу (Lamport/ctnbee/verily) і не "
                          "калібрувалось; на вільному крої великий мотив читається тихіше",
                поріг=0.30), сила_нп=сила_нп))

    # ── P-PRT-02: чіткість краю ↔ контраст особи (ЖИВЕ) ────────────────────────
    ко = None
    if F is not None:
        # п.14 (20.09.2026): без шкіри чи волосся `profile.контраст` повертає
        # `доступно=False` без винятку → `value_gap` нема → «бракує контраст_особи»
        # нижче. Виняток звідти — зіпсований профіль або збій `face_contrast`
        # (саме такий KeyError цей `except` колись ковтав — коментар у `profile.контраст`),
        # і він має летіти в `bridge.виклик`, а не читатись як «контраст не виміряно».
        import profile as _pr
        ко = _pr.контраст(F, source=source).get("value_gap")
    if чк is None or ко is None:
        нема_виміру.append(dict(правило="P-PRT-02",
                                бракує="чіткість_краю" if чк is None else "контраст_особи"))
    else:
        ко_norm = min(1.0, ко/45.0)                    # T3: ΔL*45 -> високий контраст
        розрив = abs(чк - ко_norm)
        сила_нп = round(min(1.0, розрив/1.0), 2)
        if сила_нп >= _РЕЄСТР.C["нп_підлога"]:
            бік = ("м'якшим краєм (washy, розмиті межі)" if чк > ко_norm
                   else "чіткішим краєм (визначені межі мотиву)")
            # ── ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026) ───────────
            # ТОЙ САМИЙ КЛАС, ЩО В P-PRT-01. `бік` уже посаджений рядком вище й
            # видно його тільки в `ремонт`, який на виході конвеєра з знахідки
            # зникає, а промпт друкує саму `суть`. Зміряно тим самим прогоном:
            #   before, край 0.95 проти контрасту особи 0.21 (треба М'ЯКШИЙ):
            #     · чіткість краю принту не в парі з контрастом особи [0.74]
            #   before, край 0.05 проти контрасту особи 1.00 (треба ЧІТКІШИЙ):
            #     · чіткість краю принту не в парі з контрастом особи [0.95]
            # Розрив береться по модулю, тому обидва боки дають однакове речення:
            # старий рядок каже, що пари немає, і не каже, куди рухати край.
            #   after, той самий прогін, ті самі сили:
            #     · «блуза в графічний принт»: чіткість краю не в парі з
            #       контрастом особи — узяти принт з м'якшим краєм (washy,
            #       розмиті межі) [0.74]
            #     · «сукня в акварельний принт»: чіткість краю не в парі з
            #       контрастом особи — узяти принт з чіткішим краєм (визначені
            #       межі мотиву) [0.95]
            # Ані порога, ані нормування речення не торкається: у ньому лише
            # назва речі й уже порахований `бік`.
            зн.append(dict(_РЕЄСТР._зн("P-PRT-02", _кат(сила_нп),
                "«%s»: чіткість краю не в парі з контрастом особи — "
                "узяти принт з %s" % (річ, бік), [ід],
                "чіткість краю %.2f проти контрасту особи %.2f (ΔL* %.0f)" % (чк, ко_norm, ко),
                ремонт="узяти принт з %s" % бік,
                ламається="Raes дає це для принту БІЛЯ ОБЛИЧЧЯ; на низу зв'язок слабший",
                поріг=45.0), сила_нп=сила_нп))

    # ── P-PRT-03: щільність/ґрунт ↔ камуфляж (інертне) ─────────────────────────
    if ґр is None or зона_камуфляж is None:
        нема_виміру.append(dict(правило="P-PRT-03", бракує="зона_камуфляж" if ґр is not None
                                else "ґрунт",
                                потрібно=КОНТРАКТ_ПРИНТУ["зона_камуфляж"]["потрібно"],
                                маємо=dict(ґрунт=ґр)))
    else:
        # Lamport: щільніший принт (менше ґрунту) камуфлює; розріджений з великим
        # ґрунтом створює фокус. Сила = наскільки принт розріджений там, де просили тихо.
        сила_нп = round(min(1.0, max(0.0, (ґр - 0.55)/0.40)), 2)
        if зона_камуфляж != слот_принту:
            # МОВЧАННЯ МУСИТЬ БУТИ ІМЕНОВАНИМ. Правило має обидва виміри (ґрунт і
            # зону), просто вони про різні слоти — це НЕ «бракує входу», тому
            # `бракує=None`, і не знахідка, тому в `нема_виміру` з нотою.
            нема_виміру.append(dict(правило="P-PRT-03", бракує=None,
                нота="зона камуфляжу «%s» — інший слот, ніж принтований «%s»"
                     % (зона_камуфляж, слот_принту or "не названий")))
        elif сила_нп >= _РЕЄСТР.C["нп_підлога"]:
            зн.append(dict(_РЕЄСТР._зн("P-PRT-03", _кат(сила_нп),
                "«%s»: розріджений принт створює фокус там, де просили тихо" % річ, [ід],
                "ґрунт %.2f — мотиви поодинокі на великому полі, око чіпляється" % ґр,
                ремонт="щільніший принт (менше ґрунту) або однотонне в цю зону",
                ламається="залежить від крою: на драпованому фалди руйнують фокус",
                поріг=0.55), сила_нп=сила_нп))

    # ── P-PRT-04: рух мотиву ↔ рух рис (інертне) ───────────────────────────────
    if рух is None or риси_рух is None:
        нема_виміру.append(dict(правило="P-PRT-04", бракує="рух" if рух is None else "риси_рух",
                                потрібно=КОНТРАКТ_ПРИНТУ["рух"]["потрібно"]))
    elif "мішаний" not in (рух, риси_рух) and рух != риси_рух:
        сила_нп = 0.45                                  # T3: категорійне, не градієнт
        зн.append(dict(_РЕЄСТР._зн("P-PRT-04", _кат(сила_нп),
            "рух мотиву проти руху рис", [ід],
            "мотив %s, риси %s (Raes: збіг руху читається як «її річ»)" % (рух, риси_рух),
            ремонт="узяти мотив з рухом «%s»" % риси_рух,
            ламається="один родовід (Raes); на аксесуарі далеко від обличчя не працює"),
            сила_нп=сила_нп))

    return dict(знахідки=зн, нема_виміру=нема_виміру,
                живих=len(зн), очікує=len(нема_виміру),
                нота="придатність: %d знахідок; %d правил чекають виміру" % (
                    len(зн), len(нема_виміру)))


