@lru_cache(maxsize=None)
def група(*властивості, без="", порядок=""):
    """Похідна впорядкована група слотів за властивостями таблиці.

    Поодинокий ключ слота теж є селектором. `без` віднімає властивості чи ключі;
    `порядок` лише переставляє вже вибрані слоти й не може змінити склад групи.
    Це зберігає порядок чинних позиційних пар та обходів, окремо від належності.
    """
    def вибрати(імена):
        """Об'єднати слоти відомих властивостей і ключів без здогадів."""
        вихід = set()
        for ім in імена:
            свої = {ключ for ключ, _, ознаки in ТАБЛИЦЯ.values()
                    if ім == ключ or ім in ознаки or ім == "усі"}
            if not свої:
                raise ValueError("Невідомий селектор слотів: " + ім)
            вихід.update(свої)
        return вихід
    свої = вибрати(властивості) - вибрати(без.split())
    if порядок:
        ряд = tuple(порядок.split())
        if len(ряд) != len(свої) or set(ряд) != свої:
            raise ValueError("Порядок не відповідає складу групи слотів")
        return ряд
    return tuple(с for с in СЛОТИ if с in свої)
