def тіло(зріст=164, обхвати=None):
    об = обхвати or dict(плечі=112, груди=94, талія=74, стегна=100)
    T = areas.профіль_тіла(зріст, об)
    return T, {nm: y for nm, y, *_ in T}


def збудувати(T, H, речі):
    """Речі задані рівнями тіла ('плечі'→'талія'); площа ОБЧИСЛЮЄТЬСЯ."""
    гео = areas.образ_з_геометрії(T, [
        dict(id=r["id"], верх_см=H[r["від"]], низ_см=H[r["до"]],
             припуск=r.get("крій", "straight"), покриття=r.get("покриття", 1.0))
        for r in речі])
    m = {g["id"]: g for g in гео}
    out = []
    for r in речі:
        g = m[r["id"]]
        out.append(dict(id=r["id"], слот=r["слот"], hex=r["hex"],
                        площа=g["площа"], джерело_площі=g["джерело_площі"],
                        near=g["near"] if r["слот"] not in ("сумка", "прикраси") else None,
                        **{k: v for k, v in r.items()
                           if k in ("виріз", "візерунок", "текстура", "розстібнуте")}))
    return out


