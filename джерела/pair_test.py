def _картка(o):
    return features(hx(o["hex"]["шкіра"]), hx(o["hex"]["волосся"]), hx(o["hex"]["очі"]))


def перевірити_пару(p):
    """Гейти інтейку. Повертає список причин, чому пара не йде в основний рахунок."""
    з = []
    a, b = p["до"]["особа"], p["після"]["особа"]

    d_шк = de00(hx(a["hex"]["шкіра"]), hx(b["hex"]["шкіра"]))
    d_вол = de00(hx(a["hex"]["волосся"]), hx(b["hex"]["волосся"]))
    if d_вол > GATES["картка_дрейф"]["поріг"]:
        з.append(dict(гейт="картка_дрейф", вимір=round(d_вол, 1),
                      суть=f"волосся змінилось на ΔE00={d_вол:.1f} — між кадрами "
                           "інша картка особи, отже інший контраст_особи"))

    # Освітлення оцінюється по шкірі: шкіра між кадрами не мінялась фізично.
    if d_шк > GATES["освітлення"]["поріг"]:
        з.append(dict(гейт="освітлення", вимір=round(d_шк, 1),
                      суть=f"шкіра тієї самої людини різна на ΔE00={d_шк:.1f} — "
                           "кадри зняті за різного світла/камери; абсолютні пороги "
                           "(C*, коридори нейтралей) на цій парі ненадійні"))

    if p["колірна_зміна"] == "ні":
        з.append(dict(гейт="нема_колірної_зміни", вимір=None,
                      суть="колір не є важелем цієї пари"))

    if (p["стиліст"] or "").strip().lower() in КОРПУС_СТИЛІСТИ:
        з.append(dict(гейт="перетин_з_корпусом", вимір=None,
                      суть=f"«{p['стиліст']}» — джерело правил корпусу"))
    return з


def зсув_освітлення(p):
    """Зведення кадру «після» до світла кадру «до» по шкірі тієї самої людини.

    ВИПРАВЛЕНО: тут стояв адитивний зсув у LAB. Освітлення множить сигнал, а не
    віднімає сталу, тож зсув, узятий зі шкіри (L*≈66), клав чорний светр на L*−2 —
    за межу шкали, — а сірий переводив в іншу колірну сім'ю. Перевірено на реальному
    зсуві ΔE00=9.4: усі речі діставали −12.5 L* незалежно від власної світлоти.
    Тепер — діагональне масштабування в XYZ (фон Кріс), colorspace.адаптувати."""
    la = hx(p["до"]["особа"]["hex"]["шкіра"])
    lb = hx(p["після"]["особа"]["hex"]["шкіра"])
    адаптер, інфо = адаптувати(la, lb)
    return адаптер, інфо["зсув_de00"]


# ─────────────────────────── СЛІПЕ ОЦІНЮВАННЯ ───────────────────────────
def _оцінити(F, речі, intent="conventional", source="uncontrolled"):
    """Рулбук над ОДНИМ кадром. Мітки «до/після» сюди не потрапляють — сигнатура
    їх не приймає, тож сліпота гарантована структурно, а не обіцянкою."""
    r = outfit.review(F, речі, source=source, intent=intent)
    спрац = {}
    for st, d in r["стани"].items():
        for z in d["знахідки"]:
            с = z.get("сила")
            if с in ("ok", "утримано", None):
                continue
            прв = z["правило"]
            ранг = {"hint": 1, "soft": 2, "strong": 3, "hard": 4}.get(с, 0)
            if ранг > спрац.get(прв, (0, None))[0]:
                спрац[прв] = (ранг, с)
    блокери = {k for k, (r_, s_) in спрац.items() if s_ in ("hard", "strong")}
    return dict(усі=set(спрац), блокери=блокери,
                ранги={k: v[0] for k, v in спрац.items()},
                сили={k: v[1] for k, v in спрац.items()})


def прогнати_пару(p, T, H, intent="conventional", корекція=True, seed=None):
    """Скорить обидва кадри НАосліп (порядок подачі рандомізується), мітки
    прикладаються лише після скорингу."""
    зауваги = перевірити_пару(p)
    зсув, вел = зсув_освітлення(p)

    кадри = {}
    for мітка in ("до", "після"):
        k = p[мітка]
        F = _картка(k["особа"])
        речі = збудувати(T, H, k["речі"])
        if корекція and мітка == "після":
            # Кадр «після» зводиться до світла кадру «до»: зсув береться зі шкіри
            # тієї самої людини. Речі отримують lab-канал; hex лишається для сліду.
            for r_ in речі:
                r_["colors"] = [dict(lab=зсув(hx(r_["hex"])), coverage=1.0)]
        кадри[мітка] = (F, речі)

    # ── R-CHEV-17: ЗМІШАНИЙ КОНТРАСТ — третій із трьох контрастів Chevreul ────
    # Корпус ніс два (симультанний R-CHEV-01, послідовний R-CHEV-05) і не мав третього.
    # Змішаний = комплемент, викликаний оком після фіксації, ДОДАЄТЬСЯ до наступного
    # кольору, на який дивишся. Це механізм ПОСЛІДОВНОГО ПЕРЕГЛЯДУ — а кожне судження
    # у цьому стенді робиться саме так: кадр N дивляться, щойно подивившись кадр N−1.
    #
    # ЩО ЦЕ МІНЯЄ ТУТ: рандомізації порядку НЕ ДОСИТЬ. Вона робить зсув випадковим, а
    # не нульовим: на кожній конкретній парі порядок усе одно один, і його ефект
    # лишається в результаті цієї пари. Тому пара проганяється В ОБИДВА БОКИ, і
    # розбіжність між прогонами повідомляється як `чутлива_до_порядку`.
    # Це та сама процедура, що вже застосована до нестабільності суддів (питати кожну
    # пару двічі в обох порядках і відкидати неузгоджені) — тут вона поширюється на
    # механізм, який Chevreul назвав.
    #
    # ⚠ ДЕ ЛАМАЄТЬСЯ: Chevreul часу спадання не дає. Сучасна робота з післяобразами
    # кладе корисне вікно в секунди — тобто це важить для ШВИДКОГО A/B і не важить для
    # роздивляння. Величина T4; тут не міряється жодна константа, лише фіксується,
    # чи вердикт від порядку залежить.
    def _прогін_у_порядку(пор):
        рез = {}
        for токен, мітка in enumerate(пор):          # токен, не мітка
            F, речі = кадри[мітка]
            рез[токен] = (мітка, _оцінити(F, речі, intent))
        return {мітка: res for токен, (мітка, res) in рез.items()}

    порядок = ["до", "після"]
    (random.Random(seed).shuffle(порядок) if seed is not None else random.shuffle(порядок))
    оц = _прогін_у_порядку(порядок)
    оц_зворотний = _прогін_у_порядку(list(reversed(порядок)))
    чутлива = (sorted(оц["до"]["блокери"]) != sorted(оц_зворотний["до"]["блокери"]) or
               sorted(оц["після"]["блокери"]) != sorted(оц_зворотний["після"]["блокери"]))
    nдо, nпісля = len(оц["до"]["блокери"]), len(оц["після"]["блокери"])
    напрям = "правильно" if nдо > nпісля else ("неправильно" if nдо < nпісля else "нічия")
    return dict(пара=p["id"], тип=p["тип"], колірна_зміна=p["колірна_зміна"],
                стиліст=p["стиліст"], джерело=p["джерело"],
                зауваги=зауваги, зсув_освітлення=вел,
                блокери_до=sorted(оц["до"]["блокери"]),
                блокери_після=sorted(оц["після"]["блокери"]),
                спрацювало_до=sorted(оц["до"]["усі"]),
                спрацювало_після=sorted(оц["після"]["усі"]),
                ранги_до=оц["до"]["ранги"], ранги_після=оц["після"]["ранги"],
                n_до=nдо, n_після=nпісля, напрям=напрям,
                порядок_подачі=list(порядок),
                чутлива_до_порядку=чутлива,
                порядок_нота=("вердикт МІНЯЄТЬСЯ від порядку подачі — пара має бути "
                              "відкинута з агрегації (R-CHEV-17: змішаний контраст, "
                              "механізм послідовного перегляду)" if чутлива else
                              "вердикт стійкий до порядку подачі (прогнано в обидва боки)"),
                придатна=(not зауваги) and (not чутлива))


# ─────────────────────────── АГРЕГАЦІЯ ───────────────────────────
def _знак_тест(c, w):
    """Точний двобічний біноміальний знаковий тест, p=0.5. Без scipy."""
    n = c + w
    if n == 0:
        return None
    k = max(c, w)
    хвіст = sum(math.comb(n, i) for i in range(k, n + 1)) * (0.5 ** n)
    return min(1.0, 2 * хвіст)


def звести(прогони):
    основні = [r for r in прогони if r["придатна"]]
    важкі = [r for r in основні if r["тип"] == "важка"]
    демо = [r for r in основні if r["тип"] == "демонстраційна"]

    відкинуті = {}
    for r in прогони:
        for z in r["зауваги"]:
            відкинуті.setdefault(z["гейт"], []).append(r["пара"])

    усі_з_кольором = [r for r in прогони if r["колірна_зміна"] in ("так", "частково")]
    частка_колірного_важеля = (round(len(усі_з_кольором) / len(прогони), 2)
                               if прогони else None)

    c = sum(1 for r in основні if r["напрям"] == "правильно")
    w = sum(1 for r in основні if r["напрям"] == "неправильно")
    t = sum(1 for r in основні if r["напрям"] == "нічия")

    # По кожному правилу окремо. Порівнюється СИЛА, не факт спрацювання:
    # «hard на до, hint на після» — це розрізнення, а облік по присутності
    # порахував би його як «спрацювало в обох» і сховав сигнал.
    правила = {прв: dict(до=0, після=0, однаково=0, мовчить=0)
               for прв in ЕМІТОВНІ}
    for r in основні:
        for прв in ЕМІТОВНІ:
            d = правила[прв]
            a = r["ранги_до"].get(прв, 0)
            b = r["ранги_після"].get(прв, 0)
            if a == b == 0:  d["мовчить"] += 1
            elif a > b:      d["до"] += 1
            elif b > a:      d["після"] += 1
            else:            d["однаково"] += 1
    for прв, d in правила.items():
        n = len(основні)
        якщо_мало = n < МІН_ПАР
        if d["мовчить"] == n:
            d["вердикт"] = "мовчить завжди — тест нічого про нього не каже"
        elif d["однаково"] == n:
            d["вердикт"] = "спрацьовує однаково на обох — не розрізняє"
        elif d["до"] + d["після"] == 0:
            d["вердикт"] = "без сигналу"
        else:
            d["вердикт"] = ("розрізняє" if d["до"] > d["після"] else
                            ("ЗВОРОТНИЙ напрям — правило штрафує «після»"
                             if d["після"] > d["до"] else "без сигналу"))
        if якщо_мало:
            d["вердикт"] += f" [n={n}, недостатньо]"
        d["p"] = _знак_тест(d["до"], d["після"])

    вихід = dict(
        усього_пар=len(прогони), придатних=len(основні),
        важких=len(важкі), демонстраційних=len(демо),
        відкинуто_гейтами={k: len(v) for k, v in відкинуті.items()},
        частка_пар_де_колір_є_важелем=частка_колірного_важеля,
        правильно=c, неправильно=w, нічия=t,
        по_правилах=dict(sorted(правила.items())),
        правил_у_тесті=sorted(ЕМІТОВНІ),
        виносяться_без_вердикту=sorted(НЕ_ВЕРДИКТ),
        вплетені_в_чужу_знахідку=sorted(ВПЛЕТЕНІ),
        заборона=ЗАБОРОНА_КАЛІБРУВАННЯ)

    if len(основні) < МІН_ПАР:
        вихід["вердикт"] = (f"НЕ РАХУЄТЬСЯ: придатних пар {len(основні)} < {МІН_ПАР}. "
                            "Таблиця вище — сирі рядки, не результат.")
        вихід["p"] = None
    else:
        p = _знак_тест(c, w)
        вихід["p"] = p
        частка = c / (c + w) if (c + w) else None
        вихід["вердикт"] = (f"частка правильних напрямів {частка:.2f} "
                            f"(випадковість 0.50), знаковий тест p={p:.3f}"
                            if частка is not None else "усі пари — нічия")
        if len(важкі) < МІН_ВАЖКИХ:
            вихід["вердикт"] += (f" | УВАГА: важких пар {len(важкі)} < {МІН_ВАЖКИХ}: "
                                 "результат тримається на демонстраційних, де «до» "
                                 "зроблено навмисно поганим (пастка 1)")
        if важкі:
            cw = sum(1 for r in важкі if r["напрям"] == "правильно")
            вихід["на_важких"] = f"{cw}/{len(важкі)} правильних"
    return вихід


