def _правила_модуля():
    """Знаменник тесту. Правило, яке модуль НЕ ВМІЄ винести, не може бути ні
    підтверджене, ні спростоване жодною кількістю пар — і мовчатиме не тому,
    що не спрацювало, а тому, що його нема в коді. Розрізняти ці два мовчання
    обов'язково, інакше «мовчить завжди» читатиметься як вирок правилу."""
    import inspect, re
    src = inspect.getsource(outfit)
    # 1. Оцінювані: виносяться через _зн(), тобто несуть силу hard/strong/soft/hint.
    оцінювані = set(re.findall(r'_зн\(\s*["\'](K-[A-Z]+-\d+)["\']', src))
    # 2. Виносяться, але не як вердикт (сила="питання" тощо) — рахунку не піддаються.
    інші_виносні = set(re.findall(r'правило=["\'](K-[A-Z]+-\d+)["\']', src)) - оцінювані
    # 3. Вплетені: входять у чужу знахідку як внесок (поле джерело=) або як
    #    константа-модифікатор у чужому виразі. Власного вердикту не отримають ніколи.
    вплетені = set(re.findall(r'джерело=["\'](K-[A-Z]+-\d+)["\']', src))
    вплетені |= set(re.findall(r'прав=["\'](K-[A-Z]+-\d+)["\']', src))
    вплетені -= оцінювані | інші_виносні
    # ПАРАМЕТРИ_НЕ_ПРАВИЛА нарешті щось вирішує: доти це був словник у outfit.py,
    # який ніхто не читав, хоча він прямо каже, ЯКІ ID не є самостійними твердженнями.
    # Регексна евристика вище їх не бачила — тепер вони явно виводяться зі знаменника.
    не_твердження = set(outfit.ПАРАМЕТРИ_НЕ_ПРАВИЛА)
    оцінювані -= не_твердження
    вплетені |= (не_твердження - інші_виносні)
    return оцінювані, інші_виносні, вплетені


