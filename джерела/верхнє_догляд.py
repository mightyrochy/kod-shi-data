# -*- coding: utf-8 -*-
"""верхнє_догляд.py — догляд: сольова сльота з погоди чи прапорця проти вовни, шовку й шкіри — конфлікт, який не розвʼязується (K-OUT-44/45).

Виділено з `outer.py` (19.09.2026, хвиля стандарту, СТАНДАРТ_КОДУ п.16) ЧИСТИМ
перенесенням: кожна функція й константа — байт у байт, разом із коментарями над
нею. `outer.py` лишається фасадом і реекспортує кожне ім'я звідси; цей модуль
`outer` не імпортує.
"""
import trace as _СЛ
import сценарій as _НАГОДА   # один словник опадів на систему (СТАНДАРТ §4 п.5)
from верхнє_реєстр import C, _зн, _верхній, _імʼя

# ═════════════ 9. ДОГЛЯД: КОНФЛІКТ, ЯКИЙ НЕ РОЗВʼЯЗУЄТЬСЯ ═════════════
# ⚠ ОСНОВИ, НЕ ПОВНІ ФОРМИ (11.09.2026, наряд Н-P32). Ключ — основа слова,
# значення — слово для тексту знахідки.
# ЩО ЦЕ МІНЯЄ (before/after). Список тримав ПОВНІ форми («вовна», «шкіра»,
# «замша») і шукав їх підрядком у `матеріал`. Тим часом ЄДИНИЙ автоматичний
# писач матеріалу — `feed` — пише ОСНОВУ: `МАТЕРІАЛИ_ВЕРХУ = ("екошкір",
# "замш", "нубук", …)` з власним попередженням «⚠ ОСНОВИ, НЕ ПОВНІ СЛОВА».
# Отже `"замша" in "замш"` — хибне, і виміряно це так:
#   before: догляд([{матеріал: "замш"}], реагенти=True) → []
#   after:  → K-OUT-44 («замша» у переліку вразливих) + K-OUT-45
# Тобто правило про сіль мовчало рівно на тому вході, задля якого писалось, і
# мовчало ТИХО: жодного питання, жодного сліду — воно просто не бачило слова.
# Це третій випадок того самого класу в цьому дереві («виглядатимете дешево»
# повз патерн у `language_gate`, «устілка» повз «устілці» у `feed`): патерн,
# писаний під власний приклад, ловить власний приклад.
СОЛЬОВРАЗЛИВІ = {"вовн": "вовна", "шовк": "шовк", "шкір": "шкіра",
                 "замш": "замша", "нубук": "нубук", "кашемір": "кашемір"}
_СЛОВО = __import__("re").compile(r"[а-яіїєґёa-zA-ZА-ЯІЇЄҐЁ']+")


def _основи(в, основи):
    """Основи зі списку, що стоять НА ПОЧАТКУ слова матеріалу верхнього шару.

    Читаються ТРИ поля, бо матеріал приходить трьома різними шляхами:
    `матеріал` — склад магазину (`feed.матеріал_речі`, 84 % речей слота) або
    рука, `матеріал_верху` — фід (те саме поле, яке вже читає
    `accessory.сезон_і_погода`), назва — слово магазину, коли параметра нема
    взагалі. `текстура` СЮДИ НЕ ВХОДИТЬ — див. рішення в докстрінзі `догляд`.

    ВІД ПОЧАТКУ СЛОВА, А НЕ БУДЬ-ДЕ В РЯДКУ: підрядок дав би «шовк» у
    «шовковиця» і зрівняв би «екошкіра» зі шкірою, хоча синтетика саме та, що
    сіль тримає КРАЩЕ, — тобто правило перевернулось би на своєму ж матеріалі.
    Де ламається: «штучна шкіра» двома словами сюди все ж потрапить — окремого
    списку заперечень тут навмисно нема, бо `feed` уже розрізняє «екошкір»
    перед «шкір» одним списком, і другий список означав би два джерела правди.
    """
    текст = " ".join(str(в.get(к) or "") for к in
                     ("матеріал", "матеріал_верху", "назва")).lower()
    слова = _СЛОВО.findall(текст)
    return [о for о in основи if any(с.startswith(о) for с in слова)]


# ── СЛЬОТА ВИВОДИТЬСЯ З ПОГОДИ, А НЕ ЛИШЕ З ПРАПОРЦЯ (17.09.2026) ───────────
# ЩО ТУТ БУЛО. `догляд(речі, реагенти, темп_c, опади)` читала РІВНО `реагенти`;
# `темп_c` і `опади` стояли в сигнатурі й не вживались у тілі — це названий
# випадок із `аудит/КЛАС_МЕРТВІ_ПАРАМЕТРИ.md` («порада про догляд не залежить
# від дощу»), і `pipeline.перевірити_образ` слухняно передавав туди обидва.
# ЧОМУ ЦЕ БУЛО НЕ КОСМЕТИКОЮ. `реагенти` — прапорець, який мусить поставити
# ЛЮДИНА або показ; у жодному прогоні стенда, тесту живого шляху й гейтів його
# нема. Отже K-OUT-44 і K-OUT-45 — обидва правила сольової осі теми-11 — не
# спрацьовували НІКОЛИ, і причина була не в правилі, а в тому, що єдиний їхній
# вхід ніхто не заповнює.
# ЩО СТАЛО. Сльота — це мокрий сніг біля нуля, і саме тоді дороги солять. Це
# ВИВЕДЕННЯ, не оголошення, тому воно назване окремим джерелом у знахідці:
# оголошені реагенти лишаються сильнішим входом, а погодне виведення дає
# правилу живий шлях без нового поля. Смуга температури — фольклорна константа
# з реєстру, не з джерела: жодне джерело теми не каже, за якої температури
# починають солити.
# Словник опадів — один на систему (`сценарій.py`, СТАНДАРТ §4 п.5, 19.09.2026):
# тут лишається лише ВИБІРКА з нього, бо сльота — не всяка вода, а сіль на дорозі.
СОЛЬОВІ_ОПАДИ = tuple(о for о in _НАГОДА.ОПАДИ_КАНОН if о in ("мокрий_сніг", "сніг"))


def _сльота(реагенти, темп_c, опади):
    """(чи сольова сльота, звідки це відомо). `None` у другому — сльоти нема."""
    if реагенти:
        return True, "реагенти оголошені (людина або показ)"
    опади = _НАГОДА.канон_опади(опади)
    if опади in СОЛЬОВІ_ОПАДИ and темп_c is not None and темп_c <= C["сльота_темп_c"]:
        return True, ("виведено з погоди: «%s» при %+.0f°C — дороги солять саме в цю "
                      "смугу; це ВИВЕДЕННЯ, не оголошення" % (опади, темп_c))
    return False, None


def догляд(речі, реагенти=None, темп_c=None, опади=None):
    """K-OUT-44 (хлорид кальцію найгірше діє на те, що корпус вважає ознакою якості),
    K-OUT-45 (замша під сіллю — домашній ремонт заборонено).

    ⚠ РІШЕННЯ ПРО ПОЛЕ `текстура` (11.09.2026, крок 4 наряду Н-V14-029). Ланка
    `в.get("текстура")` у ланцюзі основ була МЕРТВА за побудовою, і мертва тихо:
    `текстура` — це латинська шкала ЛЮСТРУ з `verify.СЛОВО_ТКАНИНИ` («leather»,
    «silk-shine», «satin», «denim», «knit-fine»), а СОЛЬОВРАЗЛИВІ тримає
    кириличні основи волокна. Перетин порожній, тобто поле не могло дати жодної
    знахідки ні до, ні після будь-якої правки даних.
    ОБРАНО ЗНЯТИ ПОЛЕ З ЛАНЦЮГА, а не додавати латинські синоніми. Причина не в
    обережності, а в тому, що додавання перевернуло б правило на його ж
    матеріалі: «leather» стоїть у `СЛОВО_ТКАНИНИ` ОДНАКОВО за «шкір», за «замш»
    і за «екошкір»/«кожзам». Тобто один синонім «leather» вішав би сольове вето
    на екошкіру — синтетику, яка сіль тримає КРАЩЕ за натуральну шкіру, — і
    водночас губив би замшу під словом «шкіра», позбавляючи її K-OUT-45
    (єдиного правила, де заборонено домашнє чищення). «satin» не додається з
    тієї ж причини, названої в наряді: сатин буває поліестером.
    Волокно тепер приходить тим самим шляхом, що й решта слів магазину:
    `матеріал` — цілий рядок складу (`feed.матеріал_речі`), `матеріал_верху` —
    param жниварки. Люстр лишається окремою НОТОЮ про вигляд речі: його читають
    осі формальності й блиску (`формальність.ПОЛЯРНОСТІ_ФОРМАЛЬНОСТІ`, кластери
    текстур), і жодна з них не вдає, що люстр — це волокно."""
    зн = []
    в = _верхній(речі)
    сльота, звідки = _сльота(реагенти, темп_c, опади)
    if в is None or not сльота:
        return зн
    вовна = в.get("вовна_частка")
    вразливий = [СОЛЬОВРАЗЛИВІ[о] for о in _основи(в, СОЛЬОВРАЗЛИВІ)]
    if вовна is not None and вовна >= C["вовна_частка_мін"] and "вовна" not in вразливий:
        вразливий.append("вовна")
    if not вразливий:
        # ── МОВЧАННЯ ПО СОЛІ БУВАЄ ДВОХ РІЗНИХ ВИДІВ, І ЇХ ТРЕБА РОЗВЕСТИ ─────
        # «Склад оголошено, і він стійкий» — це ПРОЙДЕНО. «Складу не оголошено» —
        # це ВІДСУТНІЙ ВХІД, і доти обидва виходили однаковим порожнім списком.
        # ВИМІРЯНО (17.09.2026, каталог_повний): склад оголошено на 501 із 618
        # речей слота «верхній_шар»; решта 117 мовчали так само, як стійка
        # синтетика. Тепер вони йдуть ПИТАННЯМ із названим блокером — той самий
        # контракт, що в `без_входу()`: «без входу» ≠ «пройдено» (K-IO-03).
        # ДРУГА МЕЖА, НАЗВАНА ТУТ ЖЕ І ВИМІРЯНА: навіть на оголошеному складі
        # K-OUT-45 у цьому каталозі не має входу — натуральної замші чи нубуку в
        # слоті «верхній_шар» НУЛЬ речей. Дві речі з ЕКОЗАМШІ правило свідомо не
        # бере: `_основи` порівнює від початку слова, а синтетика сіль тримає
        # краще за натуральну замшу. Це вимір каталогу, не дефект правила.
        if not _основи(в, ("поліестер", "нейлон", "акрил", "віскоз", "бавовн",
                           "поліамід", "еластан", "еко")) and not в.get("матеріал"):
            зн.append(dict(_зн("K-OUT-44", "питання",
                "складу верхнього шару не оголошено — сольова вісь мовчить без входу",
                [_імʼя(в)],
                "сльота: %s. Хлорид кальцію найшкідливіший для ВОВНИ, ШОВКУ й ШКІРИ й "
                "майже нешкідливий для синтетики — тобто відповідь залежить РІВНО від "
                "складу, а магазин його не назвав. Мовчати тут означало б видати "
                "«невідомо» за «стійке»" % звідки,
                ремонт="запитати склад верхнього шару — одного рядка досить",
                ламається="це ЧЕРГА НА ВХІД, а не провал речі. І межа поруч: навіть на "
                          "оголошеному складі K-OUT-45 (замша) у цьому каталозі входу "
                          "не має — натуральної замші чи нубуку в слоті нуль речей"),
                сила_нп=0.0, сила_нп_джерело="входу нема: склад не оголошено"))
        return зн
    зн.append(dict(_зн("K-OUT-44", "default",
        "сольова сльота: те, що краще за теплом, гірше за строком служби",
        [_імʼя(в)],
        "сольова сльота лишає осад хлориду кальцію, і він найшкідливіший для ВОВНИ, "
        "ШОВКУ й ШКІРИ: знебарвлює тканину, послаблює волокна, лишає шкіру сухою й "
        "вицвілою; синтетичні волокна стійкіші. Що довше сіль лишається, то глибше "
        "проникає у волокно. Тут у верхньому шарі: %s" % ", ".join(вразливий),
        ремонт=["чистити після кожного виходу — механізм часу тут вирішальний",
                "для сльоти тримати стійкіший верхній шар, вовну — для сухого морозу"],
        ламається="ПРЯМО КОНФЛІКТУЄ з K-OUT-18, який винагороджує 60–70 % вовни, і "
                  "конфлікт СПРАВЖНІЙ, не термінологічний. Вовна краща за теплом і "
                  "триманням форми й гірша за стійкістю до реагентів. Розвʼязок — не "
                  "компроміс у складі, а РОЗДІЛЕННЯ СЦЕНАРІЇВ, і воно вимагає, щоб "
                  "система знала сценарій дня, а не лише температуру. Такого входу "
                  "зараз нема, і його відсутність тепер має ціну"),
        сила_нп=0.5, сила_нп_джерело="механізм хімічний і не спірний; чисел деградації "
                                     "не дає ніхто; сльота — %s" % звідки))
    _СЛ.запис("K-OUT-44", "реагенти проти складу, конфлікт із K-OUT-18", "догляд",
              значення=",".join(вразливий), сила=0.5, напрям="ціна, не заборона")
    if _основи(в, ("замш", "нубук")):
        зн.append(dict(_зн("K-OUT-45", "default",
            "замша під сіллю: домашнє чищення ЗАБОРОНЕНО", [_імʼя(в)],
            "замша — найвразливіший матеріал щодо солі, і воду чи оцет на неї наносити "
            "НЕ МОЖНА: лишаються постійні кола. Потрібне професійне чищення",
            ремонт=["професійне чищення, не домашнє",
                    "захисний спрей для замші й нубуку тонкими шарами, з повторенням "
                    "після кожного намокання — але джерела цієї поради ці спреї "
                    "ПРОДАЮТЬ, тому вона `hint`, а не рекомендація"],
            ламається="усі знайдені джерела говорять про ВЗУТТЯ; переніс на замшеве "
                      "пальто чи дублянку зроблено ЗА МАТЕРІАЛОМ, не за джерелом. "
                      "Механізм той самий (нап убиває сіль), але це переніс, і він "
                      "позначений"),
            сила_нп=0.6,
            сила_нп_джерело="професійне джерело, механізм названий; сльота — %s" % звідки))
    _СЛ.запис("K-OUT-45", "замша під сіллю: домашнє чищення заборонено", "догляд",
              значення=звідки, сила=0.6, напрям="заборона дії, не відбір речі")
    return зн
