"""Палітрові ролі й кольори за слотами."""
import colorspace as cs
from slots import СЛОТИ_ТИПОВОГО_ОБРАЗУ
import колір_тон as _КТ   # лічба кола (середина дуги) — визначення в `колір_тон`
from колір_простір_перетворення import lab_з_lch as _lab_з_lch   # LCh → Lab — визначення в модулі перетворення
from palettes import НАСИЧЕНІСТЬ, хрома_за_насиченістю

def _hex(L, C, h):
    """«#rrggbb» із (L, C, h): хрома обрізана стелею гамуту `cs.c_max` (R-MUN-04), канали — до [0,
    255]."""
    c = min(C, cs.c_max(L, h))
    r, g, bl = cs.to_rgb(*_lab_з_lch(L, c, h))
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v * 255))) for v in (r, g, bl))

НЕЙТРАЛІ = {                       # K-COL-06: холодна сім'я ⟂ тепла
    "чорна":  ("чорний і темно-сірий",      18.0, 4.0, 250.0),
    "сіра":   ("сірий",                     55.0, 4.0, 250.0),
    "біла":   ("білий і молочний",          88.0, 4.0, 80.0),
    "нейві":  ("темно-синій",               25.0, 12.0, 265.0),
    "тепла":  ("беж, кемел, браун",         62.0, 14.0, 65.0),
    "олива":  ("олива й хакі",              48.0, 16.0, 100.0),
}

def колір_слота(v, _запас_h=None, основа=None):
    """Повертає зразок визначеного кольору або None для вільного тону.

    Другий позиційний аргумент збережено для давніх викликачів; запасний кут не є фактом.
    Обрана нейтральна основа підставляється лише в нейтральну сім'ю слота.
    """
    основа = основа or {}
    # Нейтральна основа замінює лише нейтральну сім’ю слота; кольорові ролі
    # зберігають тон схеми. Екран і бриф використовують цю саму функцію.
    if "сім_я" in v:
        нейтр = основа.get("база")
        # База — якір сама (`база_hex` + `база_тип`), таблиця сімей — запасний шлях без hex.
        # Світлота секунданта зсувається від основи (K-COL-06, ΔL*≥12): без зсуву верх і низ
        # збігалися в нейтральних гілках (перевірка #2051: 90/144).
        if основа.get("база_hex") and основа.get("база_тип") == "нейтраль":
            hx = str(основа["база_hex"]).lstrip("#")
            nL, nC, nh = cs.lch(cs.to_lab(tuple(int(hx[i:i + 2], 16) for i in (0, 2, 4))))[:3]
        elif нейтр in НЕЙТРАЛІ:
            _, nL, nC, nh = НЕЙТРАЛІ[нейтр]
        else:
            nL = None
        if nL is not None and v["роль"] in ("домінанта", "секундант"):
            зсув = 0.0 if v["роль"] == "домінанта" else (12.0 if nL < 50 else -12.0)
            return _hex(max(6.0, min(94.0, nL + зсув)), nC, nh), False
    L = (v["L"][0] + v["L"][1]) / 2.0
    C = (v["C"][0] + v["C"][1]) / 2.0
    дуга = v.get("дуга_тону")
    вільний = дуга is None
    if вільний:
        return None, True
    h = _КТ.середина_дуги(дуга)   # середина за ходом, з переходом через 0°
    if v.get("сім_я"):                       # нейтраль: хрома притиснута
        C = min(C, 10.0)
        # K-COL-06: нейтраль без дуги тону не має «вільного» кольору — запасний
        # кут (30°, рожева сім'я) лежить ПОЗА нейтральними коридорами (тепла
        # 45–115°, холодна 230–300°), тож зразок читався блідо-рожевим під
        # підписом «нейтраль». Тон бере температуру
        # нейтралі, коли вона відома («нейтраль_темп», K-COL-06-T, обидва кути —
        # усередині своїх коридорів); інакше зразок лишається ахроматом.
        темп = v.get("нейтраль_темп")
        if темп and темп.get("тепло_особи"):
            h = 80.0 if темп["тепло_особи"] > 0 else 265.0
        else:
            C = 0.0
    # НАСИЧЕНІСТЬ — ВИБІР ЛЮДИНИ, НЕ ВИМІР. Скарга з прогону: «чому всі кольори
    # приглушені». Бо вікно C* задає схема під контраст особи, а людину ніхто не
    # питав. Множник рухає лише хрому емітованого кольору; тон і світлота, які
    # несуть правила, лишаються на місці.
    C = хрома_за_насиченістю(C, v.get("_насиченість"))
    # ЦІЛЬ КОЛЬОРОВОЇ РОЛІ НЕ ОБРІЗАЄТЬСЯ ДО НЕЙТРАЛІ. Середина вікна темної основи
    # («хвоя» тональної: L*≈10, C* 24) лежить поза гамутом, і `_hex` обрізав її до #181d0e
    # (C* 10) — верх «кольорової» схеми виходив майже чорним. Тон і хрома несуть схему, тож
    # зсувається світлота: найближча до середини точка ВІКНА СЛОТА, де ця хрома ще є.
    if C > 0 and not вільний and not v.get("сім_я") and cs.c_max(L, h) < C:
        Ls = [x / 2.0 for x in range(int(v["L"][0] * 2), int(v["L"][1] * 2) + 1)]
        L = min(Ls, key=lambda x: (cs.c_max(x, h) < C, abs(x - L), -cs.c_max(x, h))) if Ls else L
    return _hex(L, C, h), вільний

def рядки_кольорів_слотів(г, слоти=СЛОТИ_ТИПОВОГО_ОБРАЗУ, запас_h=30.0, вибір=None):
    """(рядки, скільки слотів із вільним тоном) кольорів по слотах гілки розвилки: без специфікації
    — один рядок із причиною (`статус_гілки`), інакше рядок на слот з hex, часткою площі,
    допуском і названою спільною роллю; нейтральна основа підставляється лише в нейтральні
    сім'ї слотів спільною функцією `колір_слота`.

    Чому так: гілка-концепт без спец валила бриф TypeError на кожному сміливому
    намірі; однаковий hex двох слотів без названої спільної ролі
    модель читала як «зроби їх однаковими»."""
    # ── ГІЛКА БЕЗ СПЕЦИФІКАЦІЇ ВАЛИЛА БРИФ ──────────────────
    # ЩО ЦЕ МІНЯЄ (правило 3, before/after, виміряно на живому шляху
    # `bridge.виклик("запити")`). `palette.розвилка_специфікацій` не фабрикує
    # спец гілці, під яку фільтра нема: вигадувати вікна було б гірше за
    # мовчання. Гілка приходить із `спец=None` і полем `статус_гілки`, яке це
    # пояснює. Ця функція читала `г["спец"]["слоти"]` без перевірки —
    # «контраст-мисматч» такою гілкою бути перестав —
    # він бере тони базової схеми й має власну драбину світлоти, тож під
    # сміливим наміром бриф показує його кольори по слотах, як і решту схем.
    # Гілка нижче лишається для схеми, якої палітра не знає взагалі.
    #   before — намір fashion_forward / statement / editorial (усі три
    #            сміливі) додає цю гілку в розвилку, і бриф падав
    #            `TypeError: 'NoneType' object is not subscriptable` НА
    #            КОЖНОМУ прогоні. Тобто сміливий намір не «слабко працював»,
    #            а не працював зовсім, і людина бачила помилку замість образів.
    #   after  — гілка називає СЕБЕ й свою причину, кольорів не вигадує.
    # Чому не пропустити гілку мовчки: перелік «усі законні схеми» тоді
    # брехав би про повноту, а сама опція існує саме щоб бути названою.
    if not (г.get("спец") or {}).get("слоти"):
        return (["  (кольорів по слотах нема: %s)"
                 % (г.get("статус_гілки") or "unknown_scheme")], 0, None)
    вибір = вибір or {}
    from колір_річ import ВЕЛИКІ_ПОВЕРХНІ
    from внутрішня_мова import код_або_невідомо
    множ = НАСИЧЕНІСТЬ.get(вибір.get("насиченість") or "середні", 1.0)
    спец = г["спец"]["слоти"]; частки = г["пропорція"]["стратегії"][0]["частки"]
    # ── СПІЛЬНА РОЛЬ НАЗИВАЄТЬСЯ, А НЕ ЛИШЕ ВИЯВЛЯЄТЬСЯ ОДНАКОВИМ HEX ─────
    # Колір рахується на РОЛЬ, і кілька слотів можуть ділити одну: у
    # «нейтрали+акцент» взуття й сумка обидва акцент, в «аналоговій» низ і
    # взуття обидва секундант. Заголовок при цьому казав «Кольори — по
    # одному на річ», а далі дві речі діставали ІДЕНТИЧНИЙ hex без пояснення.
    # Твердження розходилось із даними, і модель читала це як «зроби їх
    # однаковими» — конкретна стилістична заява, якої ніхто не ухвалював.
    # Тепер спільна роль названа, і однаковий колір стає видимим рішенням.
    _ролі_слотів = {}
    for _сл in слоти:
        _v = спец.get(_сл)
        if _v and _v.get("L"):
            _ролі_слотів.setdefault(_v["роль"], []).append(_сл)
    вих, вільно, види = [], 0, {}
    for сл in слоти:
        v = спец.get(сл)
        if not v or not v.get("L"):
            continue
        v = dict(v, _насиченість=множ)
        hx, вільний = колір_слота(v, запас_h, основа=вибір)
        вільно += int(bool(вільний))
        ч = частки.get(v["роль"])
        # СХЕМА ВЕЛИКИХ ПОВЕРХОНЬ: частка площі — лише великим речам; сумці
        # чи взуттю «20–40 % площі образу» було б неправдою, вони тут лише відлунюють.
        # Перелік великих — той самий, яким їх добирає пул (`палітра_схеми`), не копія.
        _вел = (г["спец"].get("поверхні") == "великі")
        if _вел and сл not in ВЕЛИКІ_ПОВЕРХНІ:
            ч = None
        доля = f" — {int(ч[0]*100)}–{int(ч[1]*100)}% площі образу" if ч else ""
        if _вел and ч is None:
            доля = " — лише відлуння однієї з великих речей, не обов'язково"
        якщо = (" (тон вільний, тримай світлоту й приглушеність)" if вільний
                else " (допуск: той самий тон, ледь світліший або темніший — не інший колір)")
        _разом = [x for x in _ролі_слотів.get(v["роль"], []) if x != сл]
        спільно = (f" [роль «{v['роль']}», спільна з: {', '.join(_разом)} — "
                   f"той самий колір тут НАВМИСНЕ, це перегук; хочеш розвести — "
                   f"тримай роль, зміни світлоту]") if _разом else ""
        вих.append(f"  {сл}: {hx or 'L* %s, C* %s' % (v['L'], v['C'])}{доля}{якщо}{спільно}")
        # ТЕ САМЕ КОДАМИ (ВМ-1): частка — відсотками, допуск — fixed/free, спільна роль — коди видів
        види[код_або_невідомо("slot", сл)] = {к: v for к, v in (
            ("hex", hx),
            ("lightness_range", list(v["L"]) if вільний else None),
            ("chroma_range", list(v["C"]) if вільний else None),
            ("area", [int(ч[0] * 100), int(ч[1] * 100)] if ч else None),
            ("echo", True if (_вел and ч is None) else None),
            ("hue", "free" if вільний else "fixed"),
            ("shares_role_with", [код_або_невідомо("slot", x) for x in _разом] or None)) if v is not None}
    return вих, вільно, види
