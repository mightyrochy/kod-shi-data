# вписує фото в коробку зі шляху, WordPress без суфікса віддає оригінал.
# Мініатюри тієї самої картинки (50×50 і 110×110) після заміни зливаються в
# одну адресу — тому дублікати прибираються ДО завантаження.
_ХОРОШОП = re.compile(r"/(\d+)x(\d+)(l\d+nn\d+)/")
_WORDPRESS = re.compile(r"-(\d+)x(\d+)(\.(?:webp|jpe?g|png))$", re.I)
# OpenCart (`/image/cache/…-120x137.webp`) виглядає як WordPress, але без суфікса
# віддає 404: кеш знає лише розміри, які вже нарізав. 25union.com.ua (369 речей)
# кладе у фід поруч -120x137 і -999x999 того самого фото, а правило WordPress
# зливало обидва в одну мертву адресу, і лишалась мініатюра 120×137 (виміряно
# 19.09: -999x999 → 1600×2000, 95 КБ; без суфікса → 404; -1200x1600 → 404).
_OPENCART = re.compile(r"(/image/cache/.+)-(\d+)x(\d+)(\.(?:webp|jpe?g|png))$", re.I)


def збільшити_url(url, коробка=(1200, 1600)):
    """Адреса того самого фото у великому розмірі; інша схема — без змін."""
    м = _ХОРОШОП.search(url)
    if м:
        return url[:м.start()] + "/%dx%d%s/" % (коробка[0], коробка[1], м.group(3)) + url[м.end():]
    м = _OPENCART.search(url)
    if м:
        return url[:м.start()] + м.group(1) + "-999x999" + м.group(4)
    м = _WORDPRESS.search(url)
    if м:
        return url[:м.start()] + м.group(3)
    return url


def взяти_фото(o, скільки=6, мітка=None):
    """Усі фото речі → кеш на диску, з ознаками заглушки. Мережа тут і більше ніде.

    Кожна адреса спершу пробується великою (`збільшити_url`); не віддалась —
    береться як у фіді. `скільки` рахується по РІЗНИХ фото, а не по рядках фіду.

    МІТКА — префікс імені файла в кеші, і вона не косметична. Без неї ім'я — самий
    хеш, тож ДВІ речі з тим самим фото (варіанти однієї моделі в одній крамниці)
    ділять один файл; повний прогін чистить кеш речі одразу після її запису, і та,
    що ще міряється, лишалась без файла: 4 збої з 244 на першому прогоні
    (FileNotFoundError і cv2.imread → None). З міткою файл ділити нема з ким.
    Вибірка мітки не дає — вона кеш не чистить, і спільний файл там виграш.

    У ІМ'Я ЙДЕ ХЕШ МІТКИ, А НЕ САМА МІТКА. `cv2.imread` на Windows відкриває файл
    ANSI-викликом і кириличного шляху не бачить: id речі в імені
    («ж-00418@maxa.ua~…jpg») дав 114 збоїв «NoneType has no attribute shape» зі
    114 спроб, і сторож ночі спинив прогін на 200-й — саме те, для чого він є.
    """
    os.makedirs(КЕШ, exist_ok=True)
    префікс = (hashlib.md5(str(мітка).encode("utf-8")).hexdigest()[:10] + "-") if мітка else ""
    вих, бачені = [], set()
    for url in (list(o.get("фото") or []) or list(o.get("фото_сирі") or [])):
        великий = збільшити_url(url)
        if великий in бачені:
            continue
        бачені.add(великий)
        if len(вих) >= _обмежити_фото(скільки):
            break
        вих.append(_скачати_фото(url, великий, префікс))
    return вих


def _скачати_фото(url, великий, префікс, джерело=None):
    """Одне фото → кеш. `джерело`: «розмір», коли віддалась велика адреса, інакше «фід»."""
    зап = dict(url=url)
    try:
        # Велика адреса мусить не лише віддатись, а й РОЗКОДУВАТИСЬ: brenda.ua
        # (OpenCart) на неіснуючий розмір відповідає 200 і HTML-сторінкою,
        # тож без розкодування запасний шлях ніколи не спрацьовував.
        try:
            сирі = _качати(великий)
            im = _відкрити(сирі)
            if великий != url:
                зап["url_великий"] = великий
        except Exception:
            if великий == url:
                raise
            сирі = _качати(url)
            im = _відкрити(сирі)
        зап["джерело"] = джерело or ("розмір" if зап.get("url_великий") else "фід")
        зап["байтів"] = len(сирі)
        зап["хеш"] = hashlib.md5(сирі).hexdigest()
        шлях = os.path.join(КЕШ, "%s%s.jpg" % (префікс, зап["хеш"]))
        if not os.path.exists(шлях):
            im.save(шлях, "JPEG", quality=92)
        зап["шлях"] = шлях
        зап["розмір"] = list(im.size)
        зап["мала"] = len(сирі) < 6144
        зап["майже_біла"] = _майже_біле(im)
    except Exception as e:
        зап["помилка"] = str(e)[:120]
    return зап


# ── СТОРІНКА ТОВАРУ — коли фід дав самі заглушки (19.09.2026) ────────────────
# vilni.store, ricamare.com.ua, sezone.ua (≈ 770 речей) кладуть у фід не фото
# товару, а ті самі 12 картинок сайту в КОЖНОМУ офері (логотип, банер, іконки):
# збільшення розміру дає великий логотип, і відсів справедливо його ріже. Фото
# товару є лише на сторінці: `og:image` 1200×1800, JSON-LD `image`, галерея.
# Хорошоп перед сторінкою ставить JS-перевірку: скрипт кладе cookie
# `challenge_passed=<хеш зі сторінки>` і перезавантажує. Браузер робить те саме;
# cookie живе 30 хв і береже по хосту, тож на річ іде один запит сторінки.
_ХЕШ_ПЕРЕВІРКИ = re.compile(r'defaultHash\s*=\s*"([0-9a-f]{16,})"')
_cookie_хоста = {}


def _сторінка(url, тайм=25):
    хост = urllib.parse.urlsplit(url).netloc
    for _ in range(2):
        заг = {"User-Agent": "Mozilla/5.0 (kod-shi zbahachennya v2)"}
        if хост in _cookie_хоста:
            заг["Cookie"] = "challenge_passed=" + _cookie_хоста[хост]
        зап = urllib.request.Request(urllib.parse.quote(url, safe=":/?&=%#+@;,~!$*'()[]"), headers=заг)
        with urllib.request.urlopen(зап, timeout=тайм) as в:
            html = в.read().decode("utf-8", "replace")
        м = _ХЕШ_ПЕРЕВІРКИ.search(html)
        if not м or len(html) > 5000:
            return html
        _cookie_хоста[хост] = м.group(1)
    raise RuntimeError("перевірка сайту не пройдена")


def адреси_зі_сторінки(url, html):
    """og:image → JSON-LD image → галерея Хорошопу (файли з назвою товару, не числом)."""
    адреси = re.findall(r'<meta[^>]+property="og:image"[^>]+content="([^"]+)"', html)
    for блок in re.findall(r'<script[^>]+ld\+json[^>]*>(.*?)</script>', html, re.S):
        for знач in re.findall(r'"image"\s*:\s*(\[[^\]]*\]|"[^"]*")', блок):
            адреси += re.findall(r'"([^"]+)"', знач)
    адреси += re.findall(r'["\'](/content/images/\d+/\d+x\d+l\d+\w\w\d+/[a-z0-9-]*[a-z][a-z0-9-]*-\d+\.(?:jpe?g|webp|png))',
                         html, re.I)
    вих = []
    for а in адреси:
        а = urllib.parse.urljoin(url, а.replace("\\/", "/"))
        if not re.search(r"logo|og-logo|favicon", а, re.I) and а not in вих:
            вих.append(а)
    return вих


def фото_зі_сторінки(o, скільки=6, мітка=None):
    """Фото товару зі сторінки `o['url']` у тому ж вигляді, що `взяти_фото`."""
    префікс = (hashlib.md5(str(мітка).encode("utf-8")).hexdigest()[:10] + "-") if мітка else ""
    try:
        адреси = адреси_зі_сторінки(o["url"], _сторінка(o["url"]))
    except Exception as e:
        return [dict(url=o.get("url"), джерело="сторінка", помилка=str(e)[:120])]
    вих, бачені = [], set()
    for url in адреси:
        великий = збільшити_url(url)
        if великий in бачені:
            continue
        бачені.add(великий)
        if len(вих) >= _обмежити_фото(скільки):
            break
        вих.append(_скачати_фото(url, великий, префікс, джерело="сторінка"))
    return вих


def _обмежити_фото(n):
    return max(1, min(int(n), 12))


def позначити_одну(фото, повторів, стеля=1):
    """Заглушки ОДНІЄЇ речі; `повторів(ф)` каже, у скількох речах крамниці цей файл.

    Винесено з `позначити_заглушки` без зміни правил: повний прогін бачить речі
    потоком і не може перелічити крамницю наперед — він дає свій лічильник.

    СТЕЛЯ ПОВТОРІВ. У вибірці 60 на крамницю припадає одна-дві речі, тож будь-який
    повтор — логотип, і стеля 1 вірна. По ВСЬОМУ каталогу вона хибить: brenda.ua
    ставить те саме фото 5–9 варіантам однієї речі з 363, і при стелі 1 усі її
    фото 293×440 і 560×840 ішли б у заглушки (виміряно на пробі 30: 6 збоїв із
    30, з них brenda — хибний). Тому повний прогін піднімає стелю (див. `повний`),
    а вибірка лишається з 1.
    """
    for ф in фото:
        причини = []
        if ф.get("помилка"):
            continue
        if ф.get("мала"):
            причини.append("менша за 6 КБ")
        if ф.get("майже_біла"):
            причини.append("майже біла")
        ш, в = (ф.get("розмір") or (0, 0))
        if ш and в and max(ш / в, в / ш) > 2.6:
            причини.append("смуга %d×%d — банер, не річ" % (ш, в))
        if ш and в and max(ш, в) < 250:
            причини.append("мініатюра %d×%d" % (ш, в))
        if повторів(ф) > стеля:
            причини.append("той самий файл у інших речах крамниці")
        ф["заглушка"] = "; ".join(причини) or None
    return фото


def позначити_заглушки(речі_фото, магазини):
    """Заглушка = мала, майже біла, або той самий файл у кількох речах крамниці.

    Третя ознака — головна: логотип крамниці лежить першим фото в сотнях речей,
    і відрізняє його від справжнього фото саме повтор, а не розмір.
    """
    лічильник = collections.defaultdict(collections.Counter)
    for ід, фото in речі_фото.items():
        for ф in фото:
            if ф.get("хеш"):
                лічильник[магазини[ід]][ф["хеш"]] += 1
    for ід, фото in речі_фото.items():
        л = лічильник[магазини[ід]]
        позначити_одну(фото, lambda ф: л[ф["хеш"]] if ф.get("хеш") else 0)
    return речі_фото


