def вибірка(offers, на_слот=6, сід=17, крім=ЗАГЛУШКОВІ_КРАМНИЦІ):
    """По `на_слот` речей з кожної групи слота, сід 17, без «заглушкових» крамниць.

    Рівно по стільки з кожного слота, а не пропорційно каталогу: у пропорції
    прикрас було б 0.5 речі, а саме на них ATR і падає — прогін має це показати.
    """
    за_слотом = collections.defaultdict(list)
    for o in offers:
        if (o.get("магазин") or "") in крім:
            continue
        if not (o.get("фото") or o.get("фото_сирі")):
            continue
        try:
            с = F.слоти(o).get("слот")
        except Exception:
            с = None
        if not с:
            continue
        за_слотом[група_слота(с)].append(o)
    вих = []
    for слот in sorted(за_слотом):
        речі = sorted(за_слотом[слот], key=lambda x: x["id"])
        random.Random(сід).shuffle(речі)
        вих.extend(речі[:на_слот])
    return вих


def тип_речі(o):
    """Тип для промпту: параметр крамниці, інакше слот, інакше категорія."""
    try:
        сл = F.слоти(o).get("слот")
    except Exception:
        сл = None
    тип = (o.get("параметри") or {}).get("тип") or сл or (o.get("категорія") or "").split("/")[-1].strip()
    return (тип or "річ одягу"), сл


