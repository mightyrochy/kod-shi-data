def _число(v, lo, hi, ціле=False):
    try:
        x = float(v)
    except (TypeError, ValueError):
        return None
    x = min(hi, max(lo, x))
    return int(round(x)) if ціле else round(x, 2)


def _слово(v, дозволені, розбирач=None):
    """Слово моделі → слово словника правил; чого нема в словнику — null."""
    с = str(v or "").strip().lower() or None
    if not с:
        return None
    if с in дозволені:
        return с
    if розбирач:
        с2 = розбирач(с)
        return с2 if с2 in дозволені else None
    return None


