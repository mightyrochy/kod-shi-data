# ── ПОВНИЙ ПРОГІН ПО КАТАЛОГУ ───────────────────────────────────────────────
# Вибірка (60 речей) качала УСІ фото наперед, а потім міряла. На 12 405 речах це
# 75 тис. файлів ≈ 6 ГБ на диску і година простою GPU перед першим виміром. Тому
# повний прогін — конвеєр: качалки йдуть на N речей уперед (стеля черги = стеля
# диска), міряльники беруть готове, а кеш фото речі гине відразу після її запису.
def _не_спати(вимкнути=False):
    """Windows: не давати ноутбуку заснути, поки прогін іде (жниварка._не_спати)."""
    try:
        import ctypes
        ctypes.windll.kernel32.SetThreadExecutionState(0x80000000 if вимкнути else 0x80000001)
        return True
    except Exception:
        return False


def записати_атомарно(дані, шлях):
    """tmp + os.replace — як `жнива_збагачення.записати`: обрив не лишає півфайла.

    ЧИТАЧ НЕ МУСИТЬ ВАЛИТИ ПИСЬМЕННИКА. На Windows `os.replace` на файл, який хтось
    тримає відкритим, падає з PermissionError (WinError 5 — виміряно окремою пробою),
    а `проби/zbah_v2_повний.py` створена саме щоб читати файл ПОСЕРЕД прогону. Без
    цього циклу одна проба вночі вбивала б прогін на найближчій сотні. Не вдалось за
    п'ять спроб — ідемо далі: той самий словник ляже через 50 речей.
    """
    тимч = шлях + ".tmp"
    with open(тимч, "w", encoding="utf-8") as f:
        json.dump(дані, f, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
    for _ in range(5):
        try:
            os.replace(тимч, шлях)
            return True
        except OSError:
            time.sleep(1.5)
    return False


def прибрати_кеш(фото):
    """Файли цієї речі — з диска. 12 405 речей × 6 фото ≈ 6 ГБ, якщо лишати."""
    for ф in фото:
        ш = ф.get("шлях")
        if ш:
            try:
                os.remove(ш)
            except OSError:
                pass


def _url_крамниць(offers):
    """({магазин: {адреса: у скількох речах}}, {магазин: стеля повторів}).

    Той самий файл у крамниці видно з КАТАЛОГУ, без жодного скачування: потоковий
    прогін так дізнається про логотип уже на ПЕРШІЙ речі крамниці, тоді як
    лічильник хешів набирається лише по ходу. Стеля — п'ята частина крамниці, але
    не менше дев'яти: логотип стоїть майже в кожній речі (sezone.ua — ті самі 12
    фото в усіх 256), а варіант однієї речі повторюється в одиницях.
    """
    лічильник, речей = collections.defaultdict(collections.Counter), collections.Counter()
    for o in offers:
        м = o.get("магазин") or ""
        речей[м] += 1
        for u in {збільшити_url(x) for x in (o.get("фото") or o.get("фото_сирі") or [])}:
            лічильник[м][u] += 1
    return лічильник, {м: max(9, n // 5) for м, n in речей.items()}


def повний(offers, а):
    """Усі офери каталогу → {id: запис} у `--вихід`, з продовженням після обриву."""
    вільно = shutil.disk_usage(tempfile.gettempdir()).free / 2 ** 30
    if вільно < 5:
        raise SystemExit("на диску %.1f ГБ — мало для кешу фото, треба ≥ 5" % вільно)
    лог = open(а.лог, "a", encoding="utf-8") if а.лог else None

    def каж(текст):
        рядок = "%s  %s" % (time.strftime("%H:%M:%S"), текст)
        print(рядок, file=лог or sys.stdout, flush=True)

    готове = {}
    if а.продовжити and os.path.exists(а.вихід):
        with open(а.вихід, encoding="utf-8") as f:
            усе = json.load(f)
        готове = {к: з for к, з in усе.items() if "помилка" not in з}
        каж("продовження: у файлі %d записів, придатних %d — решту перероблю"
            % (len(усе), len(готове)))
    черга = [o for o in offers if o["id"] not in готове]
    if а.ліміт:
        черга = черга[:а.ліміт]
    каж("повний прогін: каталог %d, лишилось %d, потоків %d, качалок %d, вільно %.0f ГБ"
        % (len(offers), len(черга), а.потоки, а.качалок, вільно))
    _не_спати()

    url_лічильник, стелі = _url_крамниць(offers)
    хеші = collections.defaultdict(collections.Counter)
    зам = threading.Lock()
    вхід, фото_q, вихід_q = queue.Queue(), queue.Queue(maxsize=а.потоки * 3), queue.Queue()
    for o in черга:
        вхід.put(o)

    def качальник():
        while True:
            try:
                o = вхід.get_nowait()
            except queue.Empty:
                return
            try:
                фото = взяти_фото(o, а.фото, мітка=o["id"])
            except Exception as e:
                фото = [dict(помилка=str(e)[:150])]
            м = o.get("магазин") or ""

            def відсіяти(фото):
                with зам:
                    for ф in фото:
                        if ф.get("хеш"):
                            хеші[м][ф["хеш"]] += 1
                    позначити_одну(фото, lambda ф: max(хеші[м][ф["хеш"]] if ф.get("хеш") else 0,
                                                       url_лічильник[м][збільшити_url(ф["url"])]),
                                   стеля=стелі.get(м, 9))
            відсіяти(фото)
            # Фід і правило розміру дали самі заглушки → третій крок, сторінка товару.
            if o.get("url") and not any(ф.get("шлях") and not ф.get("заглушка") for ф in фото):
                зі_сторінки = фото_зі_сторінки(o, а.фото, мітка=o["id"])
                відсіяти(зі_сторінки)
                фото = фото + зі_сторінки
            фото_q.put((o, фото))          # черга повна → качалка чекає: це і є стеля диска

    def міряльник():
        while True:
            п = фото_q.get()
            if п is None:
                return
            o, фото = п
            try:
                з = обробити(o, фото, а.модель, показ=False)
            except Exception as e:
                з = dict(id=o["id"], магазин=o.get("магазин"),
                         помилка=("%s: %s" % (type(e).__name__, e))[:200])
            прибрати_кеш(фото)
            вихід_q.put(з)

    качалки = [threading.Thread(target=качальник, daemon=True) for _ in range(а.качалок)]
    міряльники = [threading.Thread(target=міряльник, daemon=True) for _ in range(а.потоки)]
    for т in качалки + міряльники:
        т.start()

    def сторож():
        for т in качалки:
            т.join()
        for _ in міряльники:
            фото_q.put(None)
    threading.Thread(target=сторож, daemon=True).start()

    t0, збоїв, маски = time.time(), 0, collections.Counter()
    останні = collections.deque(maxlen=200)
    n, сотня, тиша = 0, time.time(), time.time()
    while n < len(черга):
        try:
            з = вихід_q.get(timeout=60)
        except queue.Empty:
            # Мовчання довше за хвилину — це або мертвий хост фото, або завислий
            # сервер. Уночі його нікому помітити, тому воно йде в лог саме.
            каж("тиша %.0f с на %d/%d: у черзі фото %d" % (time.time() - тиша, n,
                                                           len(черга), фото_q.qsize()))
            тиша = time.time()
            continue
        тиша = time.time()
        n += 1
        готове[з["id"]] = з
        збоїв += "помилка" in з
        останні.append("помилка" in з)
        маски[(з.get("маска") or {}).get("джерело") or "—"] += 1
        if n % 50 == 0 or n == len(черга):
            записати_атомарно(готове, а.вихід)
        # СТОРОЖ НОЧІ: коли падає майже все підряд — це не каталог, а впалий сервер
        # (LM Studio чи ComfyUI). Далі йти немає сенсу: `--продовжити` перепробує.
        if len(останні) == 200 and sum(останні) >= 190:
            записати_атомарно(готове, а.вихід)
            каж("СТОП на %d: 190+ збоїв з останніх 200 — перевір LM Studio і ComfyUI" % n)
            break
        if n % 100 == 0 or n == len(черга):
            темп, сотня_с = (time.time() - t0) / n, (time.time() - сотня) / min(n, 100)
            сотня = time.time()
            # Два темпи, бо вони розходяться: середній ховає просідання, темп
            # останньої сотні показує його того ж вечора. Залишок — по останній.
            каж("%d/%d  збоїв %d (%.1f %%)  %.2f с/річ (середнє %.2f)  лишилось %.1f год  маски %s"
                % (n, len(черга), збоїв, 100.0 * збоїв / n, сотня_с, темп,
                   сотня_с * (len(черга) - n) / 3600.0, dict(маски)))
    _не_спати(вимкнути=True)
    каж("готово: %d записів у файлі, пройдено %d, збоїв %d, %.2f год"
        % (len(готове), n, збоїв, (time.time() - t0) / 3600.0))
    каж("файл: %s" % а.вихід)
    if лог:
        лог.close()
    return готове


def злити(а):
    """v2 поверх v1 у `каталог_збагачення.json.gz` — по речі, і лише де фід візьме.

    ПРАВИЛО. v2 заступає v1 ТІЛЬКИ там, де `feed._збагачення_придатне` каже «візьму».
    Непридатний v2 (збій, впевненість < 0.5, слово поза ЛЕКСИКОНОМ) поверх придатного
    v1 мовчки забрав би в речі колір — а це втрата, не оновлення. Де v2 нема або він
    непридатний, лишається v1. У фід іде сам `запис` (ключі v1), а не весь запис
    прогону: кластери, кадр і маска важать утричі більше й фідові не потрібні.

    Розпакований `каталог_збагачення.json` поруч ПРИБИРАЄТЬСЯ: `build_артефакт.
    _збагачення_вантажу` шукає його ПЕРШИМ, тож старий .json тихо поїхав би у
    вантаж замість свіжого .gz (про цю пастку сказано в докстрінгу збирача).
    """
    import gzip
    v2 = json.load(open(а.вихід, encoding="utf-8")) if os.path.exists(а.вихід) else {}
    v1 = dict(F.читати_збагачення(ТУТ))
    злите, замін, нових, слабких = dict(v1), 0, 0, 0
    for ід, з in v2.items():
        зап = з.get("запис")
        if not зап or not F._збагачення_придатне(зап):
            слабких += 1
            continue
        нових += ід not in v1
        замін += ід in v1
        злите[ід] = зап
    сирі = json.dumps(злите, ensure_ascii=False, separators=(",", ":"), sort_keys=True).encode("utf-8")
    ціль = а.злити_у or os.path.join(ТУТ, F.ЗБАГАЧЕННЯ_ІМ + ".gz")
    тимч = ціль + ".tmp"
    with gzip.open(тимч, "wb", compresslevel=9) as f:
        f.write(сирі)
    os.replace(тимч, ціль)
    голий = ціль[:-3] if ціль.endswith(".gz") else None
    if голий and os.path.exists(голий):
        os.remove(голий)
        print("прибрано розпакований %s — збирач брав би ЙОГО, не .gz" % os.path.basename(голий))
    двійок = [з for з in злите.values() if (з.get("версія") or 1) >= 2]
    # Рахується ЛИШЕ по v2: у v1 `впевненість` — самооцінка моделі, у v2 — записана
    # згода свідків, і `узгодженість_збагачення` читає їх різними гілками. Одне
    # число на обидві версії зліпило б дві різні величини в одну.
    print("v1 %d · v2 %d (непридатних %d) · замінено %d · нових %d · разом %d"
          % (len(v1), len(v2), слабких, замін, нових, len(злите)))
    print("версія 2 у %d записах, з них згода ≥ %.1f у %d — стільки речей візьмуть колір "
          "з фото проти слова крамниці" % (len(двійок), F.ЗБАГАЧЕННЯ_ЗГОДА,
          sum(1 for з in двійок if (з.get("впевненість") or 0) >= F.ЗБАГАЧЕННЯ_ЗГОДА)))
    print("%s: %d КБ (сирих %.1f МБ)" % (os.path.basename(ціль), os.path.getsize(ціль) // 1024,
                                         len(сирі) / 1e6))


# ── ПРОБА РЕФЕРЕРА ──────────────────────────────────────────────────────────
def проба_реферера(offers, на_крамницю=3):
    """Чи дають п'ять «заглушкових» крамниць справжнє фото, коли є Referer.

    V1 дістала з них 1 240 логотипів. Якщо це хотлінк-захист, з Referer байти
    будуть інші — і тоді 1 362 речі повертаються в каталог, а не списуються.
    """
    за_крамницею = collections.defaultdict(list)
    for o in offers:
        м = o.get("магазин") or ""
        if м in ЗАГЛУШКОВІ_КРАМНИЦІ and (o.get("фото") or o.get("фото_сирі")):
            за_крамницею[м].append(o)
    вих = {}
    for м, речі in sorted(за_крамницею.items()):
        random.Random(17).shuffle(речі)
        рядки = []
        for o in речі[:на_крамницю]:
            url = (o.get("фото") or o.get("фото_сирі"))[0]
            р = dict(id=o["id"], url=url)
            for мітка, реф in (("без", None), ("з", "https://%s/" % м)):
                try:
                    b = _качати(url, реферер=реф)
                    р[мітка] = dict(байтів=len(b), хеш=hashlib.md5(b).hexdigest()[:12],
                                    майже_біле=_майже_біле(_відкрити(b)))
                except Exception as e:
                    р[мітка] = dict(помилка=str(e)[:100])
            р["інші_байти"] = (р["без"].get("хеш") != р["з"].get("хеш"))
            рядки.append(р)
        вих[м] = рядки
        print("%-20s %s" % (м, json.dumps(рядки, ensure_ascii=False)[:300]), flush=True)
    return вих


