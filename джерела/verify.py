# ── СКОМПІЛЬОВАНІ МЕЖІ СЛОВА (27.08.2026) ───────────────────────────────────
# Виміряно на каталозі жниварки (7597 SKU): `re.search(рядок, t)` з динамічним
# рядком компілювався заново на КОЖНИЙ виклик, бо кількість різних шаблонів по
# всіх словниках (кольори, тканини, крої, мотиви, сезони, роди) більша за кеш
# `re` (512) — 247 тис. компіляцій, 69 с із 77 с прогону. У Pyodide на телефоні
# це хвилини на випадок. Шаблон на корінь тепер компілюється один раз.
import re as _re_m
_МЕЖА_БЕЗ_ДЕФІСА = r"(?:^|[^0-9a-zа-яіїєґ'-])"   # дефіс НЕ межа (тканини, крої…)
_МЕЖА_З_ДЕФІСОМ = r"(?:^|[^0-9a-zа-яіїєґ'])"     # дефіс — межа (кольори)
_ШАБЛОНИ = {}

def _на_межі(k, t, дефіс_межа=False):
    """Чи стоїть корінь `k` на межі слова в тексті `t`. Компіляція кешується.

    ── ПІДРЯДОК ПЕРЕД РЕГУЛЯРКОЮ (17.09.2026, швидкість) ────────────────────
    Шаблон — це МЕЖА плюс `re.escape(k)`, тобто сам корінь у ньому літеральний.
    Отже `k in t` — НЕОБХІДНА умова збігу: де підрядка нема, регулярка не може
    знайти нічого, і відповідь та сама. Це не евристика й не послаблення —
    тотожність, і саме тому вона тут дозволена.
    ЧОГО ЦЕ КОШТУВАЛО ДОТИ. Словники verify (ФОРМИ 82 корені, ВОЛОКНА, крої,
    мотиви, сезони, роди) скануються ЦІЛКОМ на кожен унікальний текст речі, а
    текстів у прогоні ~10.8 тис.: 3 332 759 викликів, 5.1 млн `re.search`,
    11.1 с профільної шкали. Переважна більшість — промахи, і промах тепер
    коштує пошуку підрядка в C, а не запуску скінченного автомата.
    """
    if k not in t:
        return False
    ключ = (k, дефіс_межа)
    ш = _ШАБЛОНИ.get(ключ)
    if ш is None:
        ш = _ШАБЛОНИ[ключ] = _re_m.compile(
            (_МЕЖА_З_ДЕФІСОМ if дефіс_межа else _МЕЖА_БЕЗ_ДЕФІСА) + _re_m.escape(k))
    return ш.search(t) is not None

# R-ONT-12 — дубль `verify.назва_кольору`: відкритий словник, чесний None замість здогаду.
def назва_кольору(текст):
    """Витягує колір із назви товару. Назва в сітці буває обрізана — тоді None,
    і це чесний None, а не здогад. Корінь шукається лише на МЕЖІ СЛОВА, інакше
    «синтетика» читалась як «синій»."""
    import re as _re
    t = (текст or "").lower()
    for п in ПАСТКИ:
        t = t.replace(п, " ")
    # Дефіс — МЕЖА слова (27.08.2026): «темно-сірий», «світло-коричневий» доти не
    # доходили до кореня — 29+24+23+15+12 SKU каталогу жниварки без кольору.
    # Складені форми з дефісом усередині («темно-син») лишаються довшим збігом.
    # СКАН СЛОВНИКА ОДИН, А НЕ ОДИН ПЛЮС ОДИН НА КОЖЕН ЗБІГ (17.09.2026, швидкість):
    # ключ `max` нижче ганяв `_на_межі` по всіх 82 коренях ЩЕ РАЗ на кожен знайдений
    # колір. Довжина найдовшого кореня рахується тут же, з тих самих збігів, і
    # порядок `знайдені` зберігається — отже нічия лишається за першим оголошеним.
    збіги = [(k, ФОРМИ[k]) for k in ФОРМИ if _на_межі(k, t, дефіс_межа=True)]
    if not збіги: return None
    найдовший = {}
    for k, n in збіги:
        if len(k) > найдовший.get(n, -1): найдовший[n] = len(k)
    # найдовший збіг виграє: «темно-син» точніше за «син»
    return max((n for _k, n in збіги), key=lambda n: найдовший[n])

