# спору, вікно і вимір читаються з сирого поля, як доти.
_ХВІСТ = re.compile(r"\s*[\[(].*$")
_В_ДУЖКАХ = re.compile(r"[\[(]\s*([^\])\[(]+)")
_МОД_У_ДУЖКАХ = {"світлий": "світло", "світла": "світло", "темний": "темно", "темна": "темно"}
# «рожево», «сіро», «чорно», «синьо» — перша половина складеного слова; «капучино»,
# «золото», «срібло», «молоко», «бордо» — цілі слова, не обрізки
_ОБРІЗАНИЙ_ПРЕФІКС = re.compile(r"^([а-щьюяєіїґ']+(ево|ово|ьо)|чорно|біло|сіро|зелено|жовто|червоно|"
                                r"блакитно|темно|світло|ніжно|блідо)$")
# «оранжевий», «малиновий», «голубий», «сиреневий» — і українські слова, тож не тут
_РОС = re.compile(r"[ыэёъ]|[а-я]ой\b|\b(черн|бел|желт|красн|фиолет|коралл)[а-я]*\b")
_РОС_МОД = (("темн", "темно"), ("светл", "світло"))
# непрямий відмінок прикметника → називний тієї ж форми (роду/числа)
_ВІДМІНКИ = (("ього", "ій"), ("ьому", "ій"), ("ого", "ий"), ("ому", "ий"), ("ою", "а"), ("ої", "а"),
             ("ими", "і"), ("их", "і"),
             # знахідний жіночого роду з назви товару: «у сіро-чорну смужку», «синю»
             ("ню", "ня"), ("ну", "на"), ("ву", "ва"), ("ту", "та"), ("ру", "ра"), ("лу", "ла"), ("ку", "ка"))


def _називний(слово):
    """Прикметник кольору в непрямому відмінку → називний тієї ж основи; інакше як є."""
    частини = слово.split("-")
    ост = частини[-1]
    for кін, заміна in _ВІДМІНКИ:
        if ост.endswith(кін) and len(ост) > len(кін) + 1:
            частини[-1] = ост[: -len(кін)] + заміна
            break
    return "-".join(частини)


def назва_показу(частина, назва_товару=""):
    """Слово поля кольору крамниці → те, що жінка бачить на картці: мала літера,
    українською, у називному, без хвостів і розміру; детальне слово крамниці
    лишається («рожево-сливова»). Слово лексикону (з фото) виходить як є. None / ""
    → як є. Свідком спору й вікном ця форма не служить — лише показом."""
    сире = str(частина or "").strip()
    if not сире:
        return частина
    т = сире.lower().translate(_АПОСТРОФИ).strip(" _.,;+")
    мод = next((м for x in _В_ДУЖКАХ.findall(т) for к, м in _МОД_У_ДУЖКАХ.items() if x.strip() == к), None)
    в_дужках = [x.strip() for x in _В_ДУЖКАХ.findall(т)]
    т = _ХВІСТ.sub("", т).split("+")[0].strip()
    токени = т.split()
    while токени and (токени[-1] in _ПРИЙМЕННИКИ or токени[-1] in ("x", "one", "+")
                      or (_ЛАТИНКА.fullmatch(токени[-1]) and not слово_крамниці(токени[-1]))):
        токени.pop()
    т = " ".join(токени).strip(" -")
    с = слово_крамниці(т) if т else None
    if т and _ОБРІЗАНИЙ_ПРЕФІКС.match(т):
        ціле = re.search(r"(?<![а-щьюяєіїґ'])%s(?:-[а-щьюяєіїґ']+)+" % re.escape(т), str(назва_товару or "").lower())
        if ціле:
            return _називний(ціле.group(0))
        с = (слово_крамниці(назва_товару) if назва_товару else None) or с
        return ("%s-%s" % (с["мод"], с["ім"]) if с["мод"] else с["ім"]) if с else сире.lower()
    if not т or not с:
        # хвіст у дужках ніс колір, а голова — ні («клітинка (моко-зелений)»)
        for x in в_дужках:
            с2 = слово_крамниці(x)
            if с2:
                return назва_показу(x)
        return т or сире.lower()
    if _РОС.search(т) or not _УКРАЇНСЬКИЙ_РЯДОК.fullmatch(т):
        м = с["мод"] or next((м for к, м in _РОС_МОД if т.startswith(к)), None)
        return "%s-%s" % (м, с["ім"]) if м and not с["ім"].startswith("темно-") else с["ім"]
    т = " ".join(_називний(x) for x in т.split())
    if мод and not т.startswith(("темно", "світло")):
        т = "%s-%s" % (мод, т)
    return т

def вікно_всередині(a, b):
    """Чи вікно `a` лежить усередині вікна `b`: кожен колір, який приймає `a`, приймає й `b`.

    Прийняття — те саме, що в `перевірити`: межі L* і C*, а тон лише при C* ≥ 10
    (нижче кут — шум). Тож вікно без дуги лежить у вікні з дугою, лише коли його
    стеля C* нижча за 10; дуга `a` має лежати в дузі `b` по колу, з переходом
    через 0° включно. Рівні вікна — теж «усередині»: строгість додає викликач."""
    if not (b[0] <= a[0] and a[1] <= b[1] and b[2] <= a[2] and a[3] <= b[3]):
        return False
    if b[4] is None or a[3] < 10:
        return True
    if a[4] is None:
        return False
    return ((a[4][0] - b[4][0]) % 360 + (a[4][1] - a[4][0]) % 360
            <= (b[4][1] - b[4][0]) % 360)


