# Це НЕ нові кольори й не нові константи: слово звужує L-вікно базового кольору до
# його темної чи світлої половини — монотонно, без порога. «темно-синій» має власне
# вікно й тут не чіпається. Де ламається: «темно-бежевий» темної половини бежевого
# (60–75) може не мати в тканині взагалі — вікно лишається зоною пошуку.
_МОДИФІКАТОРИ = {"темно": "темно", "світло": "світло", "ніжно": "світло",
                 "блідо": "світло"}

def модифікатор_світлоти(текст, ім=None):
    """«темно» / «світло» / None — лише якщо модифікатор стоїть ПЕРЕД коренем
    кольору («темно-сірий», «світло сіра»), а не десь у назві."""
    import re as _re
    t = (текст or "").lower()
    корені = [k for k in ФОРМИ if ім is None or ФОРМИ[k] == ім]
    for мод, знач in _МОДИФІКАТОРИ.items():
        for k in корені:
            if на_межі(мод + "-" + k, t.replace(мод + " ", мод + "-"), дефіс_межа=True):
                return знач
    return None

def вікно_зі_слова(текст):
    """(ім'я, вікно, модифікатор) або (None, None, None). Вікно вже звужене
    модифікатором світлоти; ім'я — базове, для лексикону й контролю."""
    ім = назва_кольору(текст)
    if not ім: return None, None, None
    в = ЛЕКСИКОН[ім]
    if ім.startswith("темно-"): return ім, в, None
    мод = модифікатор_світлоти(текст, ім)
    сер = (в[0] + в[1]) / 2.0
    if мод == "темно":   в = (в[0], сер, в[2], в[3], в[4])
    elif мод == "світло": в = (сер, в[1], в[2], в[3], в[4])
    return ім, в, мод

