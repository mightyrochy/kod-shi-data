# Слова `ВІКНА_КРАМНИЦЬ` лягають у сім'ю, куди модель клала більшість
# речей під цим словом крамниці (див. блок `ВІКНА_КРАМНИЦЬ`): лате й
# перлинний — світла нейтраль, тауп — беж / кемел, рудий і какао — коричнева,
# фуксія — червона, джинсовий — синя. Нової сім'ї нема.
СІМ_Ї_СЛІВ = _СК.СІМ_Ї_ПРОДУКТУ  # словник кольору (2.11): сім'ї слів — одне джерело з кодами
_СІМ_Я = {с: ім for ім, сл in СІМ_Ї_СЛІВ.items() for с in сл}
assert set(_СІМ_Я) == set(СЛОВА), set(СЛОВА) ^ set(_СІМ_Я)


def сім_я_слова(слово):
    """Сім'я тону слова `СЛОВА` — або None для слова поза словником."""
    return _СІМ_Я.get(слово)


# СЛОВО КРАМНИЦІ, ЩО НАЗИВАЄ ТОН (СХЕМА-КАРТКА). Картка казала
# «образ вийшов суто нейтральним» над «Піджак однобортний ніжно-рожевий» і «Туфлі Sergio Rossi
# блакитні»: вимір читав річ нейтраллю (низька хрома, холодний коридор), а крамниця називає колір.
# Сім'я слова — властивість словника (таблиця вище), тож і межа «нейтральна сім'я проти тону»
# живе тут: п'ять сімей нейтралі, решта сімей — тон. Центр вікна сюди не годиться: «ніжно-рожевий»
# (C* 5–17) має центр-нейтраль, хоч слово називає рожевий.
НЕЙТРАЛЬНІ_СІМ_Ї_СЛІВ = frozenset({"світла нейтраль", "беж / кемел", "сіра", "чорна", "коричнева"})


def слово_називає_тон(слово):
    """Чи слово `СЛОВА` називає тон (сім'я не нейтральна); слово поза словником — ні."""
    с = _СІМ_Я.get(слово)
    return с is not None and с not in НЕЙТРАЛЬНІ_СІМ_Ї_СЛІВ


def _сусід_сім_ї(lab, слово):
    """Слово ТІЄЇ Ж сім'ї, у чиє вікно вимір входить, — або None.

    Читає `перевірити`, коли вікно самого слова не зійшлось: сусідній відтінок
    однієї сім'ї («червоний» проти виміряного цегляного) — не суперечність, а
    інша назва того самого кольору. Тон, як і в `перевірити`, судиться з допуском на дріж
    кадру (`допуск_тону`): інакше сусід став би тією самою дірою, якою було «тон не
    перевірявся» — вимір, відкинутий словом за відтінком, тихо приймав би сусід. Вікно сусіда — вікно ЛЕКСИКОНУ, а не вжитку:
    вжиток слова — свідчення про САМЕ слово; сусід — лише названий відтінок тієї ж сім'ї, і
    його вжиток переніс би чужі хвости («хакі» крамниці звуть і буро-оливкове — тож через
    нього «зелений» прийняв би коричневий костюм ж-06428).

    Слова `ВІКНА_КРАМНИЦЬ` сусідом не бувають: їхні вікна взяті з
    того, як крамниці називають речі, і вони широкі («джинсовий» L*14–85, C* від 5,
    де тон ще не судиться) — як сусід вони б тихо приймали вимір, який слову
    «темно-синій» суперечить (#3b2f2f, ж-01784@feelyou.com.ua). Контроль виміру
    лишається таким, яким був до них."""
    сім = _СІМ_Я.get(слово)
    if not сім:
        return None
    L, C, h = lch(lab)
    for інше in СІМ_Ї_СЛІВ[сім]:
        if інше == слово or інше in ВІКНА_КРАМНИЦЬ:
            continue
        в = вікно_певне(інше)
        if в is None:
            continue
        Lmin, Lmax, Cmin, Cmax, дуга = в
        if not (Lmin <= L <= Lmax and Cmin <= C <= Cmax):
            continue
        if дуга and not _тон_не_суперечить(h, дуга, C):
            continue
        return інше
    return None
