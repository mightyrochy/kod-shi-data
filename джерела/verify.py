def клас_мотиву(текст):
    """Сім'я мотиву зі слова назви/опису. Найдовший корінь виграє («квітков» точніше
    за «квітк»; «однотон» б'є generic «принт», якщо стоять обидва — не стоять ніде
    в живих фідах, але порядок закріплено). None = слово мовчить, і це чесний None:
    у сітці назви обрізані, смуга часто не згадується — мовчання ≠ однотонність."""
    import re as _re
    t = (текст or "").lower()
    for п in ПАСТКИ_МОТИВУ:
        t = t.replace(п.replace("_", " "), " ")
    збіги = [(k, v) for k, v in КЛАСИ_МОТИВУ.items()
             if на_межі(k, t)]
    if not збіги:
        return dict(клас=None, за_чим=None,
                    надійність="назва мовчить — це НЕ означає, що річ однотонна")
    # «однотонний» і конкретна сім'я одночасно — суперечність назви: сім'я виграє
    сім = [x for x in збіги if x[1] not in ("принт", "однотонний")]
    пул = сім or [x for x in збіги if x[1] != "однотонний"] or збіги
    к = max(пул, key=lambda x: len(x[0]))
    return dict(клас=к[1], за_чим=sorted({x[0] for x in збіги}),
                надійність="назва прямо називає мотив; масштаб/щільність/розміщення "
                           "зі слова НЕвідомі (R-PRN-01: клас без осей — не вимір)")

