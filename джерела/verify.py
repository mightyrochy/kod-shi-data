_МЕЖА_З_ДЕФІСОМ = r"(?:^|[^0-9a-zа-яіїєґ'])"     # дефіс — межа (кольори)
_ШАБЛОНИ = {}

def _на_межі(k, t, дефіс_межа=False):
    """Чи стоїть корінь `k` на межі слова в тексті `t`. Компіляція кешується."""
    ключ = (k, дефіс_межа)
    ш = _ШАБЛОНИ.get(ключ)
    if ш is None:
        ш = _ШАБЛОНИ[ключ] = _re_m.compile(
            (_МЕЖА_З_ДЕФІСОМ if дефіс_межа else _МЕЖА_БЕЗ_ДЕФІСА) + _re_m.escape(k))
    return ш.search(t) is not None

def назва_кольору(текст):
    """Витягує колір із назви товару. Назва в сітці буває обрізана — тоді None,
    і це чесний None, а не здогад. Корінь шукається лише на МЕЖІ СЛОВА, інакше
    «синтетика» читалась як «синій»."""
    import re as _re
    t = (текст or "").lower()
    for п in ПАСТКИ:
        t = t.replace(п, " ")
    # Дефіс — МЕЖА слова (27.08.2026): «темно-сірий», «світло-коричневий» доти не
    # доходили до кореня — 29+24+23+15+12 SKU каталогу жниварки без кольору.
    # Складені форми з дефісом усередині («темно-син») лишаються довшим збігом.
    знайдені = [ФОРМИ[k] for k in ФОРМИ if _на_межі(k, t, дефіс_межа=True)]
    if not знайдені: return None
    # найдовший збіг виграє: «темно-син» точніше за «син»
    return max(знайдені, key=lambda n: max(
        len(k) for k in ФОРМИ if ФОРМИ[k] == n and _на_межі(k, t, дефіс_межа=True)))

