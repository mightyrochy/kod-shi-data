# візерунок («принт» 55, «принт львів» 27, «клітинку» 13, «смужку» 10,
# «леопард(овий)» 12), кілька кольорів («комбінований» 10, «мультиколор» 7),
# уламки поля («темно» 18, «світло» 6, «4-2» 5 — жниварка обрізала рядок), назва
# речі чи таблиця розмірів замість кольору («Спідниця з», «1sz Таблиця» 7). Там
# назва кольору з фото законна, і наступний вимір не має рахувати їх втратою
# словника — причина лягає в `колір_назва_за_чим` (`фід_збагачення.назва_кольору`).
_НЕ_КОЛІР_КІЛЬКА = ("мультиколор", "multicolor", "комбінован", "різнокольоров",
                    "кольоров", "техколір", "мікс")
_НЕ_КОЛІР_ВІЗЕРУНОК = ("квіт", "print", "pattern", "dot", "stripe", "check", "floral", "leopard")
_НЕ_КОЛІР_РІЧ = ("сукн", "спідниц", "штан", "шорт", "блуз", "жакет", "пуховик", "футболк",
                 "сорочк", "бомбер", "чобот", "ремін", "джинси", "корсет", "кардиган",
                 "светр", "пальт", "сарафан", "комбінезон", "костюм")
_НЕ_КОЛІР_РІЧ_ЦІЛИМ = frozenset({"топ", "парка", "бермуди"})
_НЕ_КОЛІР_ОПИС = ("вінтажн", "м'як", "цей")
_ПРИЙМЕННИКИ = frozenset({"з", "із", "зі", "на", "та", "і", "й", "без", "в", "у", "до"})


def не_колір_крамниці(частина):
    """Причина, чому частина поля кольору крамниці — не колір, або None.

    None не означає «колір»: слово може бути кольором, якого лексикон не знає
    («еспрессо», «кобальт» — однослівних полів з фото замало для вікна). Причина
    — коротка фраза для `колір_назва_за_чим`: уламок, візерунок, кілька кольорів,
    назва речі, таблиця розмірів, опис. Слово, яке `ФОРМИ` читають кольором
    («чорний принт»), сюди не доходить: `слово_крамниці` питає цю функцію лише
    після того, як `вікно_зі_слова` мовчить."""
    т = str(частина or "").strip().lower().translate(_АПОСТРОФИ)
    токени = _СЛОВО_ПОЛЯ.findall(т)
    if not any(len(x) >= 3 and x not in _МОДИФІКАТОРИ_ПОЛЯ for x in токени):
        return "уламок поля: модифікатор чи цифри без кольору"
    if клас_мотиву(т)["клас"] or any(x.startswith(к) for x in токени for к in _НЕ_КОЛІР_ВІЗЕРУНОК):
        return "візерунок"
    if any(x.startswith(к) for x in токени for к in _НЕ_КОЛІР_КІЛЬКА):
        return "кілька кольорів"
    if any(x.startswith(к) for x in токени for к in _НЕ_КОЛІР_РІЧ) or _НЕ_КОЛІР_РІЧ_ЦІЛИМ & set(токени):
        return "назва речі"
    if any(x.startswith("таблиц") for x in токени):
        return "таблиця розмірів"
    if any(x.startswith(к) for x in токени for к in _НЕ_КОЛІР_ОПИС):
        return "опис речі"
    if токени[-1] in _ПРИЙМЕННИКИ:
        return "уламок фрази"
    return None
# Українські літери, апостроф, дефіс і пробіл — і нічого більше: «Молочний»,
# «бузково-молочний», «нюдово білий» так; «черный» (ы), «чорний one»,
# «Білий[Серце]», «_Зелений» — ні (у назву йде слово лексикону, не сирий рядок).
_УКРАЇНСЬКИЙ_РЯДОК = re.compile(r"[а-щьюяєіїґ'’ʼ\- ]+")


def слово_крамниці(частина):
    """Одна частина поля кольору крамниці → dict(ім, вікно, мод, назва, як_є, латинка) або None.

    `ім` — слово лексикону, свідок сім'ї тону; `вікно` — його вікно, звужене
    модифікатором світлоти, як у `вікно_зі_слова`. `назва` — те, чим крамниця
    назвала колір, у вигляді для української картки: сама частина, коли вона
    написана українськими літерами (`як_є`), інакше слово лексикону з
    модифікатором («черный» → «чорний», «dark gray» → «темно-сірий», «Білий[Серце]»
    → «білий»). Спершу `ФОРМИ` (як назва товару), далі — лише для поля кольору —
    цілі слова `СЛОВА_КРАМНИЦЬ_ЛАТИНКОЮ` і `СЛОВА_КРАМНИЦЬ_ПОЛЯ`, якщо
    частина не названа не-кольором (`не_колір_крамниці`). Не колір лексикону —
    None (чесна тиша, як у `назва_кольору`)."""
    сире = str(частина or "").strip()
    т = сире.lower()
    if not т:
        return None
    ім, в, мод = вікно_зі_слова(т)
    латинка = False
    # Апостроф і злитий модифікатор вирівнюються ЛИШЕ коли сирий рядок мовчить:
    # у складеній частині («білий темносиній») `ФОРМИ` беруть «білий», і
    # вирівнювання там підмінило б свідка довшим коренем.
    т_н = _ЗЛИТИЙ_МОДИФІКАТОР.sub(r"\1-", т.translate(_АПОСТРОФИ))
    if not ім and т_н != т:
        ім, в, мод = вікно_зі_слова(т_н)
    if not ім:
        токени = _СЛОВО_ПОЛЯ.findall(т_н)
        фраза = _ФРАЗИ_ЛАТИНКОЮ.get(" ".join(_ЛАТИНКА.findall(т_н)))
        if фраза:
            ім, мод, латинка = фраза, None, True
        else:
            for i, ток in enumerate(токени):
                ім = СЛОВА_КРАМНИЦЬ_ЛАТИНКОЮ.get(ток) or СЛОВА_КРАМНИЦЬ_ПОЛЯ.get(ток)
                if ім:
                    мод = _МОДИФІКАТОРИ_ПОЛЯ.get(токени[i - 1]) if i else None
                    латинка = ток in СЛОВА_КРАМНИЦЬ_ЛАТИНКОЮ
                    break
        # «квіти бузок», «принт вишні» — візерунок, хоч слово й знайдене; латиниця
        # судиться без змін («black checkered» — свідок «чорний»)
        if not ім or (not латинка and не_колір_крамниці(т_н)):
            return None
        # «dark navy», «dark blue» → «темно-синій» власним вікном, як дає
        # `вікно_зі_слова("темно-синій")`; модифікатор над ним не звужує
        if мод == "темно" and "темно-" + ім in СЛОВА:
            ім = "темно-" + ім
        if ім.startswith("темно-"):
            мод = None
        в = вікно_вжитку(ім)
        сер = None if в is None else (в[0] + в[1]) / 2.0
        if в is None: pass
        elif мод == "темно":   в = (в[0], сер, в[2], в[3], в[4])
        elif мод == "світло": в = (сер, в[1], в[2], в[3], в[4])
    як_є = not латинка and bool(_УКРАЇНСЬКИЙ_РЯДОК.fullmatch(т))
    return dict(ім=ім, вікно=в, мод=мод, латинка=латинка, як_є=як_є,
                назва=(сире if як_є else ("%s-%s" % (мод, ім) if мод else ім)))


# ── НАЗВА КОЛЬОРУ ДЛЯ ПОКАЗУ — ЛЮДСЬКИМ УКРАЇНСЬКИМ СЛОВОМ ──
# ЩО ЦЕ ЛІКУЄ. На картці стоїть слово поля кольору крамниці «як є», а
# поле буває ВЕЛИКИМИ («ЧОРНИЙ» 20, «БІЛИЙ» 17), російською («желтый» 13,
# «ТЕМНЫЙ БЕЖ»), з хвостом («Зелений (трава)» 12, «Чорний[Абстракція]», розмір
# «Чорний ONE»), обрізане жниваркою («беж з», «темно-синій в», «Рожево» з
# «Рожево-сливова») чи в непрямому відмінку («молочного» 15, «синього»).
# ЩО РОБИТЬ. Регістр — малий; хвіст у дужках — геть (але «(світлий)» / «(темний)»
# — модифікатор: «бежевий (світлий)» → «світло-бежевий»); латинський сміттєвий
# токен і прийменник у кінці — геть; обрізаний префікс («рожево») — ціле слово з
# назви товару («рожево-сливова»), інакше слово лексикону; непрямий відмінок —
# називний тієї ж форми («молочного» → «молочний», «золотими» → «золоті»);
# російська чи латиниця — слово лексикону з модифікатором («темный беж» →
# «темно-бежевий», «ivory» → «молочний»). ДЕТАЛЬНІСТЬ КРАМНИЦІ ЛИШАЄТЬСЯ
# (власниця: «назва магазину більш детальна»): «рожево-сливова», «бузково-
# молочний», «пломбір» не зводяться до слова лексикону. Це лише ПОКАЗ: свідок
# спору, вікно і вимір читаються з сирого поля.
_ХВІСТ = re.compile(r"\s*[\[(].*$")
_В_ДУЖКАХ = re.compile(r"[\[(]\s*([^\])\[(]+)")
_МОД_У_ДУЖКАХ = {"світлий": "світло", "світла": "світло", "темний": "темно", "темна": "темно"}
# «рожево», «сіро», «чорно», «синьо» — перша половина складеного слова; «капучино»,
# «золото», «срібло», «молоко», «бордо» — цілі слова, не обрізки
_ОБРІЗАНИЙ_ПРЕФІКС = re.compile(r"^([а-щьюяєіїґ']+(ево|ово|ьо)|чорно|біло|сіро|зелено|жовто|червоно|"
                                r"блакитно|темно|світло|ніжно|блідо)$")
# «оранжевий», «малиновий», «голубий», «сиреневий» — і українські слова, тож не тут
_РОС = re.compile(r"[ыэёъ]|[а-я]ой\b|\b(черн|бел|желт|красн|фиолет|коралл)[а-я]*\b")
_РОС_МОД = (("темн", "темно"), ("светл", "світло"))
# непрямий відмінок прикметника → називний тієї ж форми (роду/числа)
_ВІДМІНКИ = (("ього", "ій"), ("ьому", "ій"), ("ого", "ий"), ("ому", "ий"), ("ою", "а"), ("ої", "а"),
             ("ими", "і"), ("их", "і"),
             # знахідний жіночого роду з назви товару: «у сіро-чорну смужку», «синю»
             ("ню", "ня"), ("ну", "на"), ("ву", "ва"), ("ту", "та"), ("ру", "ра"), ("лу", "ла"), ("ку", "ка"))


def _називний(слово):
    """Прикметник кольору в непрямому відмінку → називний тієї ж основи; інакше як є."""
    частини = слово.split("-")
    ост = частини[-1]
    for кін, заміна in _ВІДМІНКИ:
        if ост.endswith(кін) and len(ост) > len(кін) + 1:
            частини[-1] = ост[: -len(кін)] + заміна
            break
    return "-".join(частини)


def назва_показу(частина, назва_товару=""):
    """Слово поля кольору крамниці → те, що жінка бачить на картці: мала літера,
    українською, у називному, без хвостів і розміру; детальне слово крамниці
    лишається («рожево-сливова»). Слово лексикону (з фото) виходить як є. None / ""
    → як є. Свідком спору й вікном ця форма не служить — лише показом."""
    сире = str(частина or "").strip()
    if not сире:
        return частина
    т = сире.lower().translate(_АПОСТРОФИ).strip(" _.,;+")
    мод = next((м for x in _В_ДУЖКАХ.findall(т) for к, м in _МОД_У_ДУЖКАХ.items() if x.strip() == к), None)
    в_дужках = [x.strip() for x in _В_ДУЖКАХ.findall(т)]
    т = _ХВІСТ.sub("", т).split("+")[0].strip()
    токени = т.split()
    while токени and (токени[-1] in _ПРИЙМЕННИКИ or токени[-1] in ("x", "one", "+")
                      or (_ЛАТИНКА.fullmatch(токени[-1]) and not слово_крамниці(токени[-1]))):
        токени.pop()
    т = " ".join(токени).strip(" -")
    с = слово_крамниці(т) if т else None
    if т and _ОБРІЗАНИЙ_ПРЕФІКС.match(т):
        ціле = re.search(r"(?<![а-щьюяєіїґ'])%s(?:-[а-щьюяєіїґ']+)+" % re.escape(т), str(назва_товару or "").lower())
        if ціле:
            return _називний(ціле.group(0))
        с = (слово_крамниці(назва_товару) if назва_товару else None) or с
        return ("%s-%s" % (с["мод"], с["ім"]) if с["мод"] else с["ім"]) if с else сире.lower()
    if not т or not с:
        # хвіст у дужках ніс колір, а голова — ні («клітинка (моко-зелений)»)
        for x in в_дужках:
            с2 = слово_крамниці(x)
            if с2:
                return назва_показу(x)
        return т or сире.lower()
    if _РОС.search(т) or not _УКРАЇНСЬКИЙ_РЯДОК.fullmatch(т):
        м = с["мод"] or next((м for к, м in _РОС_МОД if т.startswith(к)), None)
        return "%s-%s" % (м, с["ім"]) if м and not с["ім"].startswith("темно-") else с["ім"]
    т = " ".join(_називний(x) for x in т.split())
    if мод and not т.startswith(("темно", "світло")):
        т = "%s-%s" % (мод, т)
    return т

def вікно_всередині(a, b):
    """Чи вікно `a` лежить усередині вікна `b`: кожен колір, який приймає `a`, приймає й `b`.

    Прийняття — межі L* і C*, а тон лише при C* ≥ 10 (нижче кут — шум), як у
    `перевірити`; порівнює вікна (`ВЖИТОК`, вікна металу палітри), тож поріг тону вжитку (`ТОН_ВІД_C`)
    сюди не переходить. Тож вікно без дуги лежить у вікні з дугою, лише коли його
    стеля C* нижча за 10; дуга `a` має лежати в дузі `b` по колу, з переходом
    через 0° включно. Рівні вікна — теж «усередині»: строгість додає викликач."""
    if not (b[0] <= a[0] and a[1] <= b[1] and b[2] <= a[2] and a[3] <= b[3]):
        return False
    if b[4] is None or a[3] < 10:
        return True
    if a[4] is None:
        return False
    return _дуга_в_дузі(a[4], b[4])



