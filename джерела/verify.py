    """Слово тканини як є, або None. Жодного висновку: це поле для ока й для
    моделі, правила читають свої вузькі осі. «екошкір» перед «шкір» — довший
    корінь виграє, як усюди в цьому модулі."""
    t = (текст or "").lower()
    for п in ПАСТКИ_ТКАНИНИ:
        t = t.replace(п, " ")
    збіги = [(k, v) for k, v in ВОЛОКНА.items() if _на_межі(k, t)]
    if not збіги:
        return None
    return max(збіги, key=lambda x: len(x[0]))[1]


