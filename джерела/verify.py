def у_дузі(h, дуга):
    """Чи тон h лежить у дузі (a, b) на колі відтінків.

    Дуга з переходом через 0° (a > b) перевіряється двома половинами: звичайне
    `a <= h <= b` мовчки не впізнавало б жодної червоно-пурпурової сім'ї."""
    return в_дузі(h, дуга)

def допуск_тону(C):
    """Наскільки ширшою за дугу слова судиться тон виміру з хромою `C` (градуси; 180 — не судиться).

    Метод і виміри — у блоці над `ВЖИТОК`. Вище `ТОН_ВІД_C` допуск нульовий (дуга вжитку там
    звірена на каталозі), на `ДРІЖ_AB` і нижче дріж кадру накриває все коло."""
    if C >= ТОН_ВІД_C:
        return 0.0
    return 180.0 if C <= ДРІЖ_AB else math.degrees(math.asin(ДРІЖ_AB / C))

def _дуга_з_допуском(дуга, доп):
    """Дуга, ширша за `дуга` на `доп` з обох боків, — або None, коли допуск накрив усе коло.

    None означає «тон не судиться»: розширена дуга, ширша за 360°, перевіркою вже не є, а
    `_у_дузі` прочитало б її як вузьку (a > b) і відкидало б рівно те, що приймати мусить."""
    if доп <= 0:
        return дуга
    return None if доп >= 180 or ширина(дуга) + 2 * доп >= 360 else розширити_дугу(дуга, доп)

def _тон_не_суперечить(h, дуга, C, лексикон=None):
    """Чи тон `h` виміру з хромою `C` не суперечить дузі `дуга` (допуск — `допуск_тону`).

    `лексикон` — дуга ЛЕКСИКОНУ того самого слова, коли `дуга` прийшла з ВЖИТКУ: допуск на дріж
    лягає на неї, а дуга вжитку читається як виміряна (блок над `_дуга_з_вжитку`). Без
    цього аргументу (сусід сім'ї, `_сусід_сім_ї`) допуск лягає на саму `дуга`."""
    суд = _дуга_з_допуском(дуга if лексикон is None else лексикон, допуск_тону(C))
    return суд is None or у_дузі(h, суд) or у_дузі(h, дуга)

def вікно_вжитку(ім):
    """Вікно, у якому ВИМІР може бути словом `ім` (`ВЖИТОК`); без вікна вжитку —
    вікно `ЛЕКСИКОН`. Підпис точки (`palettes.назва`) читає `ЛЕКСИКОН`, не це."""
    return ВЖИТОК.get(ім) or ЛЕКСИКОН[ім]

def _квантиль(xs, p):
    """Квантиль `p` зростаючого `xs` лінійною інтерполяцією (як `statistics.quantiles`, але без
    копіювання переліку на кожен виклик і без окремого поділу на смуги)."""
    i = (len(xs) - 1) * p
    a = int(i)
    return xs[a] + (xs[min(a + 1, len(xs) - 1)] - xs[a]) * (i - a)

def _паркан(xs, край=0.0):
    """Межі, за якими точка — викид: за парканом Тьюкі (Q1 − k·IQR, Q3 + k·IQR), а з `край` > 0 —
    ще й у крайніх `край` з того ж боку (квартилі й перцентилі — лінійною інтерполяцією)."""
    xs = sorted(xs)
    q1, q3 = _квантиль(xs, 0.25), _квантиль(xs, 0.75)
    а, б = q1 - ВЖИТОК_ПАРКАН * (q3 - q1), q3 + ВЖИТОК_ПАРКАН * (q3 - q1)
    return (min(а, _квантиль(xs, край)), max(б, _квантиль(xs, 1 - край))) if край > 0 else (а, б)

# ── ОГОРТА L*/C* — ПО ОСІ ОКРЕМО, А НА МАЛІЙ ВИБІРЦІ ВИКИД МУСИТЬ БУТИ ВІДІРВАНИЙ ─────────
# ЩО БУЛО НЕ ТАК — ДВА МІСЦЯ.
# (1) ВИКИД ПО ОДНІЙ ОСІ ЗВУЖУВАВ ОГОРТУ ДРУГОЇ: точку, що викид у C*, огорта викидала і з L*.
# Атласна сукня ж-00396@feelyou.com.ua «ніжно-рожевий» #fef0ed — L* 95.8, C* 5.2; паркан C* слова
# ставив підлогу 5.32, і разом із хромою пропадала світлота, через яку огорта L* кінчалась на 89,
# а вікно — на межі лексикону 92. Оком (аркуш кадру) — блідо-рожева сукня, а код заявляв «на фото
# інший колір». Осі незалежні: тісна хрома нічого не каже про світлоту, і навпаки.
# (2) НА МАЛІЙ ВИБІРЦІ САМ ПАРКАН ГУЛЯЄ ВІД ОДНОЇ НОВОЇ ТОЧКИ. На 20–35 точках Q1/Q3 рухаються
# від кожного нового дизайну, і крайня точка перескакує межу на десяті: кардиган ж-04426@
# likeangel.com.ua «Тауп» має L* 27.33 при парканi 27.78 (0.45!), а блуза ж-02473@ricamare.com.ua
# «Mint» — L* 51.7 при парканi 51.90 (0.2). Обидві оком свого слова; обидві стали заявами, коли
# ширша дуга додала слову по одній точці й зрушила квартилі.
# Огорта рахується ПО КОЖНІЙ ОСІ ЗІ СВОГО переліку точок, а на МАЛІЙ вибірці
# (< `ВЖИТОК_ДРІБНО` точок) крайня точка за парканом лишається вжитком, якщо вона не ВІДІРВАНА
# від решти: крок до найближчої взятої точки не більший за `ВЖИТОК_ВІДРИВ` міжквартильного
# розмаху. Це той самий принцип, що вже стоїть на дузі: межа слова — там, де РОЗРИВ, а не
# там, де перцентиль. Порогом служить IQR самого слова, тож міра безрозмірна: у слова з тісним
# ядром відрив малий, у розкиданого — великий. Ланцюжок точок упритул тягнеться, поки є крок
# ≤ порога, — і саме тому 96.7 «таупу» (майже біле) лишається викидом: від 87.9 до нього 8.8 при
# порозі 7.2, розрив є.
# ЧОМУ ЛИШЕ НА МАЛІЙ ВИБІРЦІ. На великій вибірці розривів у крайніх 5 % нема ЗОВСІМ (у
# «бежевого» 594 точки, у «червоного» 197) — відрив там нічого не відрізав би, і чорна підошва
# під «бежевим» повернулась би у вікно. Перевірено й відкинуто простіший варіант «послабити
# паркан до 2.0·IQR для всіх»: він лагодить ті самі три речі, але заодно тягне «червоний» L*
# 13–65 → 5–80, «шоколадний» 51 → 61, «коричневий» 60 → 67 і «бежевий» 33–97 → 30–100, тобто
# знімає контроль, який поставлено оком. Відкинуто й «межі щільністю від лексикону,
# без квантилів зовсім» (як дуга): на щільних словах ланцюжок біжить через увесь розмах —
# «чорний» дістає L* 0–100 C* 0–35, «білий» L* 57–100, «червоний» L* 5–100.
# Вікно ширшає у 10 слів із 47 (з них 8 — на 1–4 одиниці). Вікно лексикону — підлога: вужчим
# вікно вжитку не стає.
def _огорта_осі(xs):
    """(найменше, найбільше) вжитку по ОДНІЙ осі й лічба викидів — з точок `xs` цієї осі.

    Викид — точка за `_паркан`, а на вибірці, меншій за `ВЖИТОК_ДРІБНО`, ще й відірвана від
    решти (метод — у блоці вище). Без точок — (None, None, 0)."""
    xs = sorted(xs)
    if not xs:
        return None, None, 0
    ниж, вер = _паркан(xs, ВЖИТОК_КРАЙ)
    у = [x for x in xs if ниж <= x <= вер]
    if not у:
        return xs[0], xs[-1], 0
    if len(xs) < ВЖИТОК_ДРІБНО:
        поріг = ВЖИТОК_ВІДРИВ * (_квантиль(xs, 0.75) - _квантиль(xs, 0.25))
        а, б = у[0], у[-1]
        while True:
            крок = [x for x in xs if x < а and а - x <= поріг]
            if not крок:
                break
            а = max(крок)
        while True:
            крок = [x for x in xs if x > б and x - б <= поріг]
            if not крок:
                break
            б = min(крок)
        у = [x for x in xs if а <= x <= б]
    return у[0], у[-1], len(xs) - len(у)

# ── ДУГА ВЖИТКУ — ЩІЛЬНІСТЮ, А НЕ ПАРКАНОМ ─────
# ЩО БУЛО НЕ ТАК. Дугу вжитку давав паркан Тьюкі на відхилі тону від кругового середнього, а
# дуга, ширша за стелю (100°), відкидалась ЦІЛКОМ — слово лишалося з дугою ЛЕКСИКОНУ, тобто
# найгірший випадок не діставав розширення зовсім. На круговому розподілі з двома кінцями (те
# саме слово і на буро-оливковому, і на петролі) паркан не ріже викид — він ріже хвіст, а
# стеля-вимикач знімає всю правку. Оком (27 аркушів кадру з плашкою виміру поруч):
# «тауп» (39–72°) не брав ЛІЛОВОГО таупу — костюм ж-01793@stolyarchuk.com.ua виміряний
# hex 897680, тон 343°, оком тауповий; «зелений» (100–180°) не брав ТЕМНОГО СМАРАГДУ — спідниця
# ж-07262@natalibolgar.com #1d303a, тон 243°, оком зелена.
# Дуга росте З ДУГИ ЛЕКСИКОНУ (ВЖИТОК ⊇ ЛЕКСИКОН) смугами по
# `ВЖИТОК_КРОК`° з кожного боку: смуга з хоч однією точкою вжитку тягне край дуги на цю точку
# (край — по крайній ТОЧЦІ, а не по межі смуги). `ВЖИТОК_ПРОГАЛИНА` порожніх смуг підряд
# терпиться — брак речей на 15° не є межею слова, — а дві порожні підряд межу й означають.
# Зростання спиняє `ВЖИТОК_ДУГА_МАКС` — рейка, не вимикач: найширша дуга на каталозі «зелений»
# 210° (34–244°), бо крамниці й справді звуть зеленим від буро-оливкового до петролю.
# ТОЧКА ГОЛОСУЄ ЗА ДУГУ, ЛИШЕ КОЛИ ЇЇ ХРОМА ВИЩА ЗА `ДРІЖ_AB`. Нижче код і сам каже, що тону
# там немає («дріж кадру накриває все коло», `допуск_тону`), — і саме ці точки розмивали дугу:
# у «зеленого» майже чорні речі C* 1–5 стоять на тоні 213–345° (hex 232323 має C* 0,0), у
# «молочного» їх 613 із 667. Точки нижче `ТОН_ВІД_C` за дугу не голосують ЗОВСІМ — тому
# «тауп» і не знає про свій ліловий вжиток: його єдина лілова точка має C* 9,6.
# ДОПУСК НА ДРІЖ ЛЯГАЄ НА ДУГУ ЛЕКСИКОНУ, А ДУГА ВЖИТКУ ЧИТАЄТЬСЯ ЯК ВИМІРЯНА
# (`_тон_не_суперечить`): допуск — це припущення про НЕЗМІРЯНИЙ зсув кадру, а в кадрах, з яких
# зросла дуга вжитку, той зсув уже є. Додати допуск і на них означало б рахувати дріж двічі — і
# саме так пропала б виявлений випадок: графіт C* 7,7 тон 25° (кадр `polo_chocolate` речі
# ж-03040@solmar.com.ua) при дузі «зеленого» 34–244° з допуском ±51° проходив би знову.
# РІСТ ПОЧИНАЄТЬСЯ ЛИШЕ СУМІЖНОЮ СМУГОЮ.
# ЩО БУЛО НЕ ТАК. `ВЖИТОК_ПРОГАЛИНА` терпіла порожню смугу й НА САМОМУ КРАЇ лексикону — тож
# згусток, відірваний від слова, тягнув дугу до себе, а далі вона йшла вже від нього й ковтала
# все підряд. «М'ятний»: `ФОРМИ` кладуть «фісташковий» у «м'ятний» (словники заморожені
# власником), смуга 105–120° у слова порожня, зате 90–105° має 3 фісташкові дизайни
# fromus (#75690b, #cfbd5e, #e1d278) — і далі впритул ішли БЕЖЕВІ кадри під словом «м'ятний»
# (75–90°: #c6b49e, #9b9286, #c9bca9; 60–75°: #eadcd3, #ab7c58), аж дуга сягала 61–244° (183°).
# Оком (аркуш кадру з плашкою виміру): ж-02351@gepur.com «м'ятний» #ab7c58 — карамельний
# кроп-топ і штани, а заяву «на фото інший колір» код зняв, бо вимір лежав у дузі. Одна
# крамницина помилка в слові вчила слово приймати таку саму помилку.
# Прогалина бриджить дірку ВСЕРЕДИНІ хвоста вжитку, а не відкриває його: смуга,
# суміжна з дугою лексикону, мусить мати хоч одну точку, інакше сторона не росте зовсім. Якщо
# вжиток слова не дотягує навіть до власної межі словника, то за діркою стоїть не хвіст слова,
# а окремий згусток — інший колір під тим самим словом (рішення власника: вікно слова визначає
# вжиток крамниць, але кадр ЯВНО іншого кольору вікна не розширює). Лілового «таупу» це не
# чіпає: його смуга 24–39° має точку (тон 31°), і ріст до 343° іде без змін.
# ВІДОМА ВАДА (потрібне слово власника). «Фісташковий» у `ФОРМИ` — це «м'ятний»,
# тож справді фісташкова річ судиться вікном м'ятного: ж-02956@fromus.ua #e1d278 (лаймова
# футболка) дістає заяву «на фото інший колір» хибно, а ж-02963 і ж-05880 дістають її й без цього
# (їх відкидають межі L*/C*, не дуга). Без окремого слова «фісташковий» у `ЛЕКСИКОНІ` це не
# лагодиться, а словники власник заморозив.
# Дуга лексикону вужча за вжиток у 37 слів із 47 хроматичних; майже нейтральні дизайни свого слова
# лежать у його дузі в 99 % (1 473 з 1 489).
def _дуга_з_вжитку(тони, дуга):
    """Дуга лексикону `дуга`, розширена смугами по `ВЖИТОК_КРОК`° до вжитку слова.

    `тони` — тони точок, чия хрома вища за `ДРІЖ_AB`; метод — у блоці вище. `порожніх` починає
    з `ВЖИТОК_ПРОГАЛИНА`, а не з нуля: перша смуга за межею лексикону мусить мати точку, інакше
    сторона не росте (блок «РІСТ ПОЧИНАЄТЬСЯ ЛИШЕ СУМІЖНОЮ СМУГОЮ» вище)."""
    межі = list(дуга)
    for бік, знак in ((0, -1), (1, 1)):
        назовні = lambda h, від: хід(h, від) if знак < 0 else хід(від, h)
        край, новий, порожніх = дуга[бік], дуга[бік], ВЖИТОК_ПРОГАЛИНА
        while порожніх <= ВЖИТОК_ПРОГАЛИНА and (
                ширина(межі) + ВЖИТОК_КРОК <= ВЖИТОК_ДУГА_МАКС):
            у = [h for h in тони if 0 < назовні(h, край) <= ВЖИТОК_КРОК]
            if у:
                новий = межі[бік] = max(у, key=lambda h: назовні(h, дуга[бік]))
                порожніх = 0
            else:
                порожніх += 1
            край = (край + знак * ВЖИТОК_КРОК) % 360
        межі[бік] = новий
    return (math.floor(межі[0]) % 360, math.ceil(межі[1]) % 360)


def вікно_з_вжитку(точки, вікно):
    """(вікно вжитку або None, лічба) з точок (L, C, h) дизайнів слова і його вікна `ЛЕКСИКОН`.

    Метод — у блоці над `ВЖИТОК`. Дугу хроматичного слова дає щільність вжитку
    (`_дуга_з_вжитку`) від дуги лексикону; далі в L* і C* ідуть точки в дузі й усі майже
    нейтральні (C* < `ТОН_ВІД_C`; чужий тон серед них тримає суд виміру, не вікно — блок
    нижче). L* і C* — без викидів, огорта решти ∪ вікно лексикону; менше `ВЖИТОК_МІН` точок —
    межі лексикону, а дуга однаково розширена (на дугу треба менше точок, ніж на огорту).
    Без точок — None."""
    Lmin, Lmax, Cmin, Cmax, дуга = вікно
    лч = dict(дизайнів=len(точки), нейтральних=0, нп_поза_дугою=0, поза_дугою=0, викидів=0,
              дуга_вжитку=None)
    if not точки:
        return None, лч
    if дуга is not None:
        хр = [т for т in точки if т[1] >= ТОН_ВІД_C]
        дуга = _дуга_з_вжитку([т[2] for т in точки if т[1] > ДРІЖ_AB], дуга)
        лч["дуга_вжитку"] = дуга if дуга != вікно[4] else None
        # МАЙЖЕ НЕЙТРАЛЬНА ТОЧКА ВХОДИТЬ У ВІКНО, ЯК І ДОТИ, — навіть коли її тон слову
        # суперечить (`нп_поза_дугою` — лічба, не гейт). ВИМІРЯНО й ВІДКИНУТО варіант, де такі
        # точки в огорту не йдуть: на каталозі він відкидає не 40 вимірів, а 69, і зайві 29 —
        # це не чужі кольори, а звужені межі. Викидається їх мало (бежевий 6, м'ятний 2), але
        # огорта — опукла: бежевий втрачає L*33–36 і 97 (18 вимірів, темний тауп і майже біле
        # екрю), а м'ятний, у якого точок ледь за `ВЖИТОК_МІН`, від мінус двох точок падає
        # нижче стелі (21 → 19) і лишається з вікном ЛЕКСИКОНУ (L*65–92, C* 8–40 проти
        # 52–92, 2–43) — 14 вимірів блідих м'ятних речей. Це той самий принцип, що вже стоїть
        # вище: «вужчим за лексикон не стає — брак речей не доказ проти слова», і власник
        # власник просив саме не звужувати («м'ятний і оливковий — різні відтінки»). Чужий тон
        # тепер тримає СУД виміру (`перевірити`), і тримає точніше, ніж межа L*.
        нейтр = [т for т in точки if т[1] < ТОН_ВІД_C]
        лч["нейтральних"] = len(нейтр)
        лч["нп_поза_дугою"] = sum(1 for т in нейтр
                                  if not _тон_не_суперечить(т[2], дуга, т[1], вікно[4]))
        лч["поза_дугою"] = len(хр) - sum(1 for т in хр if у_дузі(т[2], дуга))
        точки = нейтр + [т for т in хр if у_дузі(т[2], дуга)]
    if len(точки) < ВЖИТОК_МІН:
        return (Lmin, Lmax, Cmin, Cmax, дуга), лч
    Lа, Lб, викL = _огорта_осі([т[0] for т in точки])
    Cа, Cб, викC = _огорта_осі([т[1] for т in точки])
    лч["викидів"] = викL + викC
    лч["огорта"] = (math.floor(Lа), math.ceil(Lб), math.floor(Cа), math.ceil(Cб))
    о = лч["огорта"]
    return (min(Lmin, о[0]), max(Lmax, о[1]), min(Cmin, о[2]), max(Cmax, о[3]), дуга), лч

def перевірити(lab, назва=None, свотч=None, допуск_свотча=18.0, ім=None):
    """Вимір проти двох свідків. Повертає вердикт і причину — щоб відкинутий
    вимір можна було розібрати, а не просто втратити.

    `ім` — ключ `ЛЕКСИКОН` замість тексту `назва`: слово крамниці вже прочитане
    (`слово_крамниці`), і читати його вдруге `назва_кольору` не можна — 13 ключів ця
    функція не впізнає («джинсовий», «тауп», «рудий», «цегляний»…, «малиновий» → «червоний»),
    і вимір тоді йшов «без контролю», тобто мовчки за згоду."""
    L, C, h = lch(lab)
    вихід = dict(L=round(L,1), C=round(C,1), h=round(h,1), вердикт="прийнято", причини=[])
    кол = ім if ім in ЛЕКСИКОН else назва_кольору(назва)
    вихід["колір_у_назві"] = кол
    if кол:
        # ВІКНО ВЖИТКУ, А НЕ ПІДПИСУ: питання тут — чи може вимір бути цим словом
        # крамниці, і відповідає на нього вжиток слова в каталозі (`ВЖИТОК`, блок над ним)
        Lmin, Lmax, Cmin, Cmax, дуга = вікно_вжитку(кол)
        проблеми = []
        if not (Lmin <= L <= Lmax): проблеми.append(f"L*{L:.0f} поза [{Lmin},{Lmax}]")
        if not (Cmin <= C <= Cmax): проблеми.append(f"C*{C:.0f} поза [{Cmin},{Cmax}]")
        # Тон СЛОВА З ДУГОЮ судиться завжди — при малій хромі з допуском на дріж кадру
        # (`допуск_тону`, блок над `ВЖИТОК`). Нижче `ТОН_ВІД_C` він не судився б зовсім, і
        # хроматичне слово брало б будь-який майже нейтраль: графіт C* 7.7 тон 25° проходив як
        # «зелений». «Молочна блуза» C* 7.7 тон 3° лишається прийнятою — її дуга (45, 110)
        # з допуском 32° накриває 3°, — а слово без дуги (нейтраль) судиться за C*.
        if дуга:
            # Дуга ВЖИТКУ — як виміряно; допуск на дріж — на дугу ЛЕКСИКОНУ (блок вище)
            доп, лекс = допуск_тону(C), ЛЕКСИКОН[кол][4]
            суд = _дуга_з_допуском(лекс, доп)
            if у_дузі(h, дуга):
                pass
            elif суд is None:
                вихід.setdefault("нотатки", []).append(
                    f"тон не судився: C*{C:.1f} ≤ {ДРІЖ_AB:.0f}, дріж кадру накриває все коло")
            elif у_дузі(h, суд):
                вихід.setdefault("нотатки", []).append(
                    f"тон {h:.0f}° поза дугою вжитку {дуга}, але в дузі лексикону {лекс} "
                    f"з допуском ±{доп:.0f}° на дріж (C*{C:.1f})")
            else:
                проблеми.append(f"тон {h:.0f}° поза {дуга}"
                                + (f" і поза {лекс} з допуском ±{доп:.0f}° на дріж (C*{C:.1f})"
                                   if доп else ""))
        if проблеми:
            # ── СУСІДНІЙ ВІДТІНОК ТІЄЇ Ж СІМ'Ї — НЕ СУПЕРЕЧНІСТЬ ──
            # ЩО ЦЕ МІНЯЄ. Зони лексикону звужені (рішення власника: «краще більше
            # кольорів, ніж одне слово на багато відтінків»), і вузьке вікно саме по
            # собі зробило б контроль суворішим там, де він і так помиляється: `feed`
            # уже записав оком, що з 16 розібраних відкидань 6 — сусідні відтінки
            # (пудровий/беж, графіт/чорний). Сім'я слів (`СІМ_Ї_СЛІВ`) заведена саме
            # для питання «чи два свідки про той самий колір»; тут вона й відповідає.
            # Вимір, який лежить у вікні слова ТІЄЇ Ж сім'ї, приймається — і сусід
            # НАЗВАНИЙ полем, а не проглинутий мовчки. Інша сім'я лишається
            # відкиданням: «червоний» проти виміряного зеленого — суперечність.
            сусід = _сусід_сім_ї(lab, кол)
            if сусід:
                вихід["сусід_сім_ї"] = сусід
                вихід.setdefault("нотатки", []).append(
                    f"назва каже «{кол}», а вимір лежить у вікні «{сусід}» — сусідній "
                    f"відтінок тієї ж сім'ї ({сім_я_слова(кол)}): " + "; ".join(проблеми))
            else:
                вихід["вердикт"] = "відкинуто"
                вихід["причини"].append(f"назва каже «{кол}», а вимір: " + "; ".join(проблеми))
    if свотч is not None:
        d = de00(lab, свотч if isinstance(свотч, tuple) else hx(свотч))
        вихід["ΔE00_до_свотча"] = round(d, 1)
        if d > допуск_свотча:
            вихід["вердикт"] = "відкинуто"
            вихід["причини"].append(f"розходження зі свотчем ΔE00={d:.0f} > {допуск_свотча:.0f}")
    if not кол and свотч is None:
        вихід["вердикт"] = "без контролю"
        вихід["причини"].append("ні назва, ні свотч не дають чим перевірити — "
                                "вимір іде далі з поміткою, а не як підтверджений")
    return вихід


# ── МЕМОІЗАЦІЯ ТЕКСТОВИХ РОЗБИРАЧІВ ─────────────────────
# `_на_межі` ганяє десятки регулярок на кожну річ, а речей у прогоні 10 770, і
# кожна проходить тут кілька разів (пул, суд, пакет): 17 с власного часу.
# Результат залежить лише від тексту, тож кешується за ним.
def _копія(v):
    """Копія значення кеша замість `copy.deepcopy`.

    Розбирачі нижче віддають РІВНО словники, списки, кортежі й скаляри — жодного
    циклу, жодного власного класу. На такому дереві `deepcopy` робить те саме, що
    цей обхід, і платить за загальність: таблицею `memo` по `id()` і диспетчером
    типів (виміряно: 542 900 викликів `deepcopy`, 4.9 млн `id()`, 1.2 с профільної
    шкали з 25.7). Спільна гілка всередині значення тут дублюється замість
    лишитись спільною — і це саме те, чого кеш і хоче: віддане назовні дерево не
    має ділити жодного змінного вузла ні з кешем, ні з попереднім викликачем.
    """
    if isinstance(v, dict):
        return {k: _копія(x) for k, x in v.items()}
    if isinstance(v, list):
        return [_копія(x) for x in v]
    if isinstance(v, tuple):
        return tuple(_копія(x) for x in v)
    return v


def _мемо_за_текстом(f):
    """Мемоїзує `f` за аргументами й віддає КОПІЮ результату.

    Копія обов'язкова: викликачі цього модуля правлять повернуті словники на місці,
    і спільний об'єкт у кеші роздавав би чужі правки наступному виклику. Нехешовані
    аргументи не кешуються взагалі (а не падають), а кеш має стелю 300 000 записів —
    після неї нові пари просто не лягають, і пам'ять не росте без межі."""
    import functools as _ft
    кеш = {}
    @_ft.wraps(f)
    def w(*a, **k):
        """Обгортка: ключ з аргументів → кеш → копія; нехешований ключ іде повз кеш."""
        try:
            ключ = (a, tuple(sorted(k.items())))
            hash(ключ)
        except TypeError:
            return f(*a, **k)
        if ключ in кеш:
            return _копія(кеш[ключ])
        v = f(*a, **k)
        if len(кеш) < 300000:
            кеш[ключ] = v
        return _копія(v)
    return w

