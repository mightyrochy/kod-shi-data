def поза_смугою_тканини(смуга, темп_c):
    """°C, на скільки день виходить за сезонну смугу тканини (0 — у смузі).

    Холодний бік не діє на холодну тканину (нижній край ≤ `НИЖНІЙ_КРАЙ_ХОЛОДНИХ`):
    вовна в мороз — у сезоні. Теплий бік діє на всіх (вовна в спеку), холодний — на
    літні (льон у мороз). Один предикат на пул і суд."""
    lo, hi, т = float(смуга[0]), float(смуга[1]), float(темп_c)
    холодний = 0.0 if lo <= НИЖНІЙ_КРАЙ_ХОЛОДНИХ else lo - т
    return max(0.0, т - hi, холодний)

