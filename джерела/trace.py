# -*- coding: utf-8 -*-
"""СЛІД: які правила спрацювали НА ЦЬОМУ профілі, з числом і напрямком.

ЩО ЦЕ МІНЯЄ В РІШЕННІ (правило 3, before/after).
  before — на питання «яке саме правило дало цю різницю між рукою B і рукою C»
           відповіді не існувало в принципі. Лог мав рядки брифа й ярлики
           («одна_лінія», «кольори не мої»), але не мав кодів корпусу, тож
           перехресна таблиця «правило × рука × вердикт» не будувалась.
  after  — кожен запис несе ID корпусу поруч із ярликом і зі значенням, на
           якому правило спрацювало. Вердикт судді тепер приписується коду.

ЧОМУ ЦЕ ОКРЕМИЙ МОДУЛЬ, А НЕ ПОЛЕ В ПАКЕТІ.
  Правила спрацьовують у пʼятьох різних модулях на трьох різних глибинах
  виклику. Протягнути «список знахідок» аргументом крізь усі означало б
  переписати сигнатури, і половина точок спрацювання все одно лишилась би поза
  ним. Акумулятор на рівні модуля коштує один рядок у точці спрацювання.

  ЦІНА, І ВОНА НАЗВАНА: акумулятор глобальний. Це безпечно рівно доти, доки
  один виклик моста виконується від початку до кінця без паралельних викликів
  (Pyodide в браузері — однопотоковий, CPython-стенд викликає послідовно). За
  паралельних викликів сліди двох профілів змішаються. Захисту від цього нема;
  щойн зʼявиться паралелізм, це має стати контекстом виклику, а не модулем.

ЩО ЦЕ НЕ МІРЯЄ (правило 6).
  · Слід каже, що правило спрацювало, і не каже, що воно спрацювало ПРАВИЛЬНО.
    Правильність знімається вердиктом людини над зібраним образом.
  · Правило, яке НЕ спрацювало на цьому профілі, у сліді відсутнє, і це не те
    саме, що «правило мертве». Розрізняє їх лише батарея профілів.
"""

_ЗАПИСИ = []
_УВІМК = False


def почати():
    """Один виклик моста = один слід. Викликається на вході, не в кінці."""
    global _ЗАПИСИ, _УВІМК
    _ЗАПИСИ = []
    _УВІМК = True


def запис(правило, ярлик, де, значення=None, сила=None, напрям=None, донор=False):
    """Правило спрацювало ТУТ і ось на чому.

    `правило` — ID корпусу або None. None дозволено й означає рівно одне:
        рядок є, а правила під ним у корпусі не знайдено. Це чесніше за
        приписування найближчого схожого ID, бо приписаний навмання ID
        зробив би перехресну таблицю судді неправдивою.
    `значення` — число чи короткий рядок, на якому воно спрацювало.
    `сила` — 0–1, якщо правило її рахує; None, якщо воно бінарне.
    `донор` — це рука C (плацебо на донорському тілі), а не рука B.
    """
    if not _УВІМК:
        return
    _ЗАПИСИ.append(dict(правило=правило, ярлик=ярлик, де=де,
                        значення=значення, сила=сила, напрям=напрям,
                        рука=("C" if донор else "B")))


def зібрати():
    """Слід без дублів. Дубль — той самий (правило, де, рука, значення):
    одне правило, що спрацювало на пʼятьох кандидатах кольору, — це одна
    знахідка з пʼятьма спрацюваннями, а не пʼять знахідок."""
    бачені, вих = set(), []
    for з in _ЗАПИСИ:
        к = (з["правило"], з["де"], з["рука"], str(з["значення"]))
        if к in бачені:
            for x in вих:
                if (x["правило"], x["де"], x["рука"], str(x["значення"])) == к:
                    x["спрацювань"] = x.get("спрацювань", 1) + 1
                    break
            continue
        бачені.add(к)
        вих.append(dict(з, спрацювань=1))
    return вих


def ід_у_сліді():
    """Множина ID корпусу, що лишили слід. Це те, що рахує гейт досяжності."""
    return {з["правило"] for з in _ЗАПИСИ if з["правило"]}


def без_ід():
    """Рядки, що спрацювали БЕЗ ID корпусу. Цей список має бути видимим:
    він і є та частина брифа, яку неможливо приписати жодному правилу."""
    return sorted({(з["ярлик"], з["де"]) for з in _ЗАПИСИ if not з["правило"]})
