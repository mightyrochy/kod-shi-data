def _рядки_від_рис(спец):
    """Вікна каталогу від рис — ОКРЕМИМИ рядками поруч зі схемними, не замість.
    Той самий патерн, що вже стоїть для `принт_ехо` і «якір-нейтраль»: шар
    retrieval пробує обидва, порожнє одне з двох не означає порожній слот.

    L і C беруться з ГОТОВОГО вікна слота без змін — рядок відрізняється від
    схемного РІВНО дугою тону. Тому будь-яка різниця у видачі приписується осі
    тону, а не побічній зміні світлоти чи хроми."""
    тв = спец.get("тон_від_рис") or {}
    if not тв.get("придатно"): return []
    рядки = []
    for s, v in спец["слоти"].items():
        if "сім_я" in v: continue                  # нейтральний слот тону не несе
        if v.get("попередження"): continue         # вироджена роль: кольору там не буває
        for nm, дані in тв["риси"].items():
            for d in дані.get("дуги", []):
                lo, hi = d["дуга"]
                обрана = (дані.get("рід") == "обрана")
                r = dict(слот=s, L_min=v["L"][0], L_max=v["L"][1],
                         C_min=v["C"][0], C_max=v["C"][1],
                         h_from=lo, h_to=hi, нейтраль=False,
                         роль=v.get("роль"),
                         джерело_тону=("макіяж:%s" % дані.get("зона") if обрана
                                       else "риса:%s" % nm),
                         риса=nm, відношення=тв["відношення"], обрана=обрана,
                         тиск_центр=d["тиск_центр"], тиск_межі=d["тиск_межі"],
                         чому=(("дуга виведена з ОБРАНОГО кольору макіяжу «%s»: це "
                                "не вимір людини, а рішення, яке вона вже ухвалила "
                                "й яке саме може бути невдалим. Рядок знімається "
                                "окремо від рис, і його НЕ можна подавати з тією ж "
                                "силою, що дугу шкіри" % дані.get("зона"))
                               if обрана else
                               ("дуга виведена з ТОНУ РИСИ «%s», не з якоря-схеми; "
                                "риси не усереднюються — це окремий рядок на кожну"
                                % nm)))
                # перегук: та сама дуга підтримана ДРУГОЮ рисою — це сильніший рядок,
                # і він мусить бути видимий, бо саме він відрізняє «одна риса каже»
                # від «дві риси кажуть те саме»
                хто = [p["риси"] for p in тв["перегуки"] if nm in p["риси"]]
                if хто: r["перегук_з"] = sorted({x for p in хто for x in p if x != nm})
                напр = [p for p in тв["напруги"] if nm in p["риси"]]
                if напр: r["напруга_з"] = [dict(риси=p["риси"], суть=p["суть"]) for p in напр]
                # Куля K-MUA-01 тут БІЛЬШЕ НЕ СТАВИТЬСЯ: вона накладається на всі
                # рядки слота одним проходом у `запит_у_фід` (див. `_кулі_слотів`).
                рядки.append(r)
    # ── ПЕРЕГУК ЯК ОКРЕМЕ, ВУЖЧЕ ВІКНО ───────────────────────────────────────
    # Спільна дуга двох рис — не те саме, що дуга кожної з них: вона вужча й
    # спирається на дві незалежні риси. Без окремого рядка ця різниця зникала б
    # у диз'юнкції «пройшов хоч одне вікно».
    for p in тв["перегуки"]:
        for a in p["спільні_дуги"]:
            зн = тиск_знахідка((a[0] + (((a[1] - a[0]) % 360) / 2)) % 360, тв["h_шкіри"])
            for s, v in спец["слоти"].items():
                if "сім_я" in v or v.get("попередження"): continue
                # Перегук між ДАНОЮ рисою й ОБРАНИМ кольором макіяжу — теж обраний:
                # інакше помада проходила б у фід непідписаною, через задні двері
                # резонансу, поки прямий її рядок чесно марковано. Рівно та тиха
                # протічка, проти якої вся ця розмітка й заведена.
                обрана_п = any((тв["риси"].get(x) or {}).get("рід") == "обрана"
                               for x in p["риси"])
                рядки.append(dict(
                    слот=s, L_min=v["L"][0], L_max=v["L"][1],
                    C_min=v["C"][0], C_max=v["C"][1],
                    h_from=a[0], h_to=a[1], нейтраль=False, роль=v.get("роль"),
                    джерело_тону="перегук:%s" % "+".join(p["риси"]),
                    риси=list(p["риси"]), Δтемпература=p["Δтемпература"],
                    тиск_центр=(зн["сила_нп"] if зн else 0.0), обрана=обрана_п,
                    чому=("спільна дуга двох рис: вужча за кожну окремо і спирається "
                          "на дві риси, а не на одну"
                          + (". ⚠ одна з них — ОБРАНИЙ колір макіяжу, тож рядок "
                             "успадковує його рід і знімається разом із ним"
                             if обрана_п else ""))))
    return рядки


# ТУТ СТОЯЛА `_дуги_перетинаються(a, b, запас=0.0)` — знесена 19.09.2026, бо
# рішення, заради якого вона існувала, більше не приймається (рядок 8 дошки
# тріажу; `досяжність.py` називав її єдиним «НІХТО»).
# ЧОМУ. Вона була предикатом ПРОПУСКУ: «дуга сім'ї бодай торкається дуги схеми
# із запасом 20° → рядок їде у фід ЦІЛИМ». `запит_у_фід` кликала її з `_у_схемі`.
# 17.09 K-PAL-01 (`da9bd05`) замінила це рішення на ОБРІЗАННЯ: рядок несе
# перетин двох дуг (`_перетин_дуг` нижче), бо виміряно було, що при пропуску
# сім'я «синя» (195–240°) торкалась «тональної» схеми (160–184°) запасом і
# віддавала в пул усі 29 своїх речей, жодна з яких у дузі схеми не лежить.
# Обрізання строго сильніше за пропуск: порожній перетин — це і є «не
# торкається». Отже другого місця виклику для неї нема й бути не може, а
# лишати в ядрі функцію, яка втілює скасоване рішення, — це залишити напоготові
# спосіб повернути ту саму протічку одним рядком. Форма повернення в неї теж
# інша (bool проти дуги), тож підміна одна на одну неможлива.
def _перетин_дуг(a, b):
    """Перетин двох дуг тону як ОДНА дуга, або None. Градуси по колу, з переходом через 0.

    Повертається найдовший зв'язний шматок перетину: рядок запиту несе рівно одну
    пару (`h_from`, `h_to`), і два шматки в ній не вмістити. На дугах сімей корпусу
    (`palettes.СІМ_Ї`, ≤ 60°) і дугах схем (≤ 60°) два шматки не трапляються —
    для цього одна з дуг мусила б бути довшою за 300°.
    """
    def _гр(д):
        """Цілі градуси дуги `д` = (від, до) по колу, з переходом через 0; (x, x) — усе коло."""
        lo, hi = float(д[0]), float(д[1])
        n = int(((hi - lo) % 360) or 360)
        return [int(lo + i) % 360 for i in range(n + 1)]
    спільні = set(_гр(a)) & set(_гр(b))
    if not спільні:
        return None
    # найдовший зв'язний шматок на колі: йдемо від градуса, чий попередник не спільний
    початки = [g for g in спільні if (g - 1) % 360 not in спільні]
    if not початки:                       # спільне — усе коло
        return (0.0, 359.0)
    найкраща = None
    for п in початки:
        довж = 0
        while (п + довж + 1) % 360 in спільні:
            довж += 1
        if найкраща is None or довж > найкраща[1]:
            найкраща = (п, довж)
    п, довж = найкраща
    return (float(п), float((п + довж) % 360))

def запит_у_фід(спец):
    """Пласка форма під SQL/XML-фільтр: те, що реально піде в інджест каталогу.

    ДОДАНО: якщо специфікація несе принт, ехо-запит виходить ОКРЕМИМ рядком на той
    самий слот (а не перезаписує його базове вікно) — з полем `сила`, щоб шар
    retrieval міг спершу спробувати ехо, а тоді відступити до базового вікна.
    Без цього ехо жило в специфікації й не доходило до фіду."""
    запити = []
    for s, v in спец["слоти"].items():
        r = dict(слот=s, L_min=v["L"][0], L_max=v["L"][1], C_min=v["C"][0], C_max=v["C"][1],
                 h_from=(v.get("дуга_тону") or (None, None))[0],
                 h_to=(v.get("дуга_тону") or (None, None))[1],
                 нейтраль=("сім_я" in v), спроба=0)
        нт = v.get("нейтраль_темп")
        if нт:      # напрям B: температурне вікно нейтралі доходить до фільтра каталогу
            r["b_min"], r["b_max"] = нт["b_min"], нт["b_max"]
            r["температура_сила"] = нт["сила_переваги"]
        запити.append(r)
        # СІМ'Ї СХЕМИ ВЕЛИКИХ ПОВЕРХОНЬ (рядок 133): кожна інша сім'я схеми — окремим
        # основним рядком того самого слота, зі своєю світлотою й хромою. Поле є лише в
        # тріади й приглушеної комплементарної (`специфікація`), тож решта схем дає
        # рівно ті самі рядки, що й доти.
        for д in v.get("дуги_схеми") or ():
            запити.append(dict(слот=s, L_min=д["L"][0], L_max=д["L"][1],
                               C_min=д["C"][0], C_max=д["C"][1],
                               h_from=д["дуга"][0], h_to=д["дуга"][1], нейтраль=False,
                               спроба=0, роль="сім'я_схеми:%s" % д["роль"],
                               чому="схема великих поверхонь: у пулі кожної великої речі "
                                    "стоять усі її сім'ї, першою — сім'я ролі слота"))
    for s, v in спец["слоти"].items():
        q = v.get("принт_ехо")
        if q:
            # `спроба=1`: ехо — це ЗАПАСНЕ вікно поруч із базовим («шар retrieval міг
            # спершу спробувати ехо, а тоді відступити»), а не другий рівноправний
            # рядок. Досі пріоритет жив у коментарі й у полі `сила`, якого ніхто не
            # читав як черговість, — тепер він стоїть у рядку числом.
            запити.append(dict(q, слот=s, спроба=1))
    # ── ЯКІРНІ СЛОТИ МУСЯТЬ МАТИ ЩЕ Й НЕЙТРАЛЬНЕ ВІКНО ──────────────────────
    # ЗНАЙДЕНО НАСКРІЗНИМ ПРОГОНОМ НА РЕАЛІСТИЧНОМУ КАТАЛОЗІ, і жодним шаровим
    # стендом: жодне взуття не проходило ЖОДНОГО вікна. Причина — усі чотири схеми
    # давали для «взуття» вікно з `нейтраль=False` і `C_min ≥ 14`, бо роль слота
    # «секундант», тобто кольоронесуча.
    # У реальному каталозі взуття, сумки й пояси — переважно НЕЙТРАЛІ: чорний,
    # бежевий, нюд, коричневий, білий. Виміряно на фікстурі: чорний C*4.4,
    # бежевий C*17.5 при h 76 — жоден не влучає у вимогу хроми з дугою тону.
    # Наслідок був тихий і повний: `feed.покриття` звітував «порожньо» на кожному
    # взуттєвому вікні, композитор відступав до «перших N без колірного критерію»,
    # і колірний шар на цьому слоті не працював ЗОВСІМ — на будь-якому фіді.
    #
    # ⚠ ЦЕ НЕ СКАСОВУЄ кольорового вікна: кольорове взуття існує й лишається
    # придатним. Додається ДРУГИЙ рядок, а не заміна — так само, як зроблено для
    # `принт_ехо` вище. Шар retrieval пробує обидва; порожнє одне з двох більше не
    # означає порожній слот.
    # Температурне вікно нейтралі (b*) береться те саме, що вже порахувала
    # `нейтраль_якір` у `специфікація` (поле `якір_нейтраль_темп`), тож нового
    # знання тут нема — лише доставка наявного туди, де його бракувало.
    # ⚠ ДОТИ ЦЕЙ КОМЕНТАР ОПИСУВАВ МЕХАНІЗМ, ЯКОГО НЕ БУЛО: рядок читав
    # `нейтраль_темп`, яке ставиться лише СХЕМНО-нейтральному слотові, а якірний
    # рядок додається саме тому, що слот схемно КОЛЬОРОВИЙ. Гілка була недосяжна
    # за побудовою — 0 із 456 рядків (Н-palette-2-099).
    for s, v in спец["слоти"].items():
        if s not in ЯКІРНІ_СЛОТИ: continue
        якщо_вже = any(q.get("слот") == s and q.get("нейтраль") for q in запити)
        if якщо_вже: continue
        нт = v.get("якір_нейтраль_темп") or {}
        # ── СВІТЛОТА ЯКІРНОЇ НЕЙТРАЛІ НЕ ОБМЕЖУЄТЬСЯ СМУГОЮ СХЕМИ ────────────
        # Друга проба показала, що самого нейтрального вікна МАЛО: з `L_min/L_max`
        # схеми (51–66) чорний черевик (L*10) і бежевий човник (L*71) далі не
        # проходили, і слот лишався порожнім.
        # Причина концептуальна, не арифметична. Смуга світлоти схеми — це план
        # КОЛІРНОЇ РОЛІ (секундант тримає середню світлоту). Для якірної нейтралі
        # ролі «секундант» нема: чорний човник працює і зі світлим, і з темним низом.
        # Те, що справді обмежує світлоту взуття, — КРОК СВІТЛОТИ до сусідньої речі
        # (K-COL-01) і когерентність нейтралей (K-CLR-02), а вони перевіряються на
        # ЗІБРАНОМУ образі, а не при доборі.
        # Отже смуга схеми тут ДУБЛЮВАЛА нижчий за течією гейт СТРОГІШОЮ й ІНШОЮ
        # умовою — і ціною цього був порожній слот на будь-якому фіді.
        # Вікно добору лишає температурне обмеження (воно про людину) і знімає
        # світлотне (воно про образ, і його перевіряють там, де образ уже є).
        r = dict(слот=s, L_min=0.0, L_max=100.0,
                 C_min=0.0, C_max=НЕЙТРАЛЬ_C_СТЕЛЯ,
                 h_from=None, h_to=None, нейтраль=True,
                 роль="якір-нейтраль",
                 # ── ЗАПАСНИЙ, А НЕ РІВНОПРАВНИЙ (Н-palette-2-098) ────────────
                 # Вікно L 0–100 × C 0–24 × будь-який тон у диз'юнкції «пройшов хоч
                 # один рядок» пропускало 97 % слота «взуття»/«сумка»: колірний шар
                 # на слотах-якорях ставав порожнім твердженням «підходить усе».
                 # Рядок додали проти ПОРОЖНЬОГО слота, і саме цю роль він і має
                 # виконувати — запасну. `спроба=1` каже це споживачеві числом:
                 # `feed.покриття` і `composer` беруть його ЛИШЕ там, де основна
                 # хвиля не дала жодного кандидата.
                 спроба=1,
                 L_не_обмежено="крок світлоти (K-COL-01) і когерентність нейтралей "
                               "(K-CLR-02) перевіряються на ЗІБРАНОМУ образі; "
                               "дублювати їх строгішою смугою при доборі означає "
                               "спорожнити слот",
                 чому="слот «%s» у реальному каталозі переважно нейтральний; "
                      "кольорове вікно лишається окремим рядком" % s)
        if нт.get("b_min") is not None:
            r["b_min"], r["b_max"] = нт["b_min"], нт["b_max"]
            r["температура_сила"] = нт.get("сила_переваги")
        запити.append(r)
    # ── ТОН ВІД ЛЮДИНИ (крок 1 задачі 42) ───────────────────────────────────
    # Рядки додаються ПОРУЧ зі схемними, а не замість: це дві різні осі («тон від
    # речі-якоря» і «тон від риси»), і зводити їх в одне вікно означало б знову
    # усереднити те, що корпус вимагає тримати окремо.
    # Тут стояло читання однойменного ключа зі спец як «кеш, якщо хтось порахував
    # раніше». Ніхто ніколи не рахував: аудит контрактів назвав це полем-сиротою
    # (читається, не пишеться ніде). Обіцянка кешу без записувача — не оптимізація,
    # а зайва гілка, що вдає, ніби вище по течії щось є. Виклик один, кеш зайвий.
    # (Імʼя ключа в коментарі НЕ відтворюється дослівно: сканер контрактів читає
    #  текст модуля, і згадка виразу воскресила б сироту, яку правка щойно зняла.)
    import personal_palette as _PP
    for r in _рядки_від_рис(спец):
        # ранг риси — ПОРЯДОК за Perrett 2023 (очі > волосся ≈ шкіра), макіяж завжди останній
        рід = _PP.рід_риси(r.get("риса") or "") if r.get("риса") else None
        r["ранг_риси"] = _PP.РАНГ_РИС.get(рід, 9) if рід else (
            min((_PP.РАНГ_РИС.get(_PP.рід_риси(x) or "", 9) for x in (r.get("риси") or [])), default=9))
        запити.append(r)
    # ── РЯДКИ З ПЕРСОНАЛЬНОЇ ПАЛІТРИ (24.08.2026) ────────────────────────────
    # Нейтралі від волосся/шкіри з b*-вікном і смугою світлоти ЛЮДИНИ; акценти від
    # очей. Це перші рядки, у яких L і C йдуть від людини, а не від схеми.
    # СІМ'Я ПАЛІТРИ ПОЗА ДУГОЮ СХЕМИ В ПУЛ НЕ ЙДЕ (16.09.2026). Доти рядки практичної
    # палітри додавали на КОЖЕН слот усі сім'ї людини (6 із 12 секторів тону), і
    # обрана схема не звужувала пул ні на річ. Нейтральні рядки лишаються: нейтраль
    # законна під будь-яку схему; кольорові — лише ті, чия дуга перетинає дугу
    # схеми для цього слота (із запасом 20°). Слоти без дуги не фільтруються.
    # ДУГА СІМ'Ї ОБРІЗАЄТЬСЯ ДУГОЮ СХЕМИ, А НЕ ЛИШЕ ПРОПУСКАЄТЬСЯ ЧЕРЕЗ НЕЇ
    # (K-PAL-01, 17.09.2026). 16.09 тут стояв ПРОПУСК: рядок сім'ї їхав у фід
    # ЦІЛИМ, якщо його дуга бодай торкалась дуги схеми із запасом 20°. Наслідок
    # виміряний на стенді (гілка 0, схема «тональна» 160–184°, каталог_повний):
    # сім'я «синя» (195–240°) торкалась запасом — і віддавала в пул усі 29 своїх
    # речей, жодна з яких у дузі схеми не лежить; «зелена» (150–190°) і «очі»
    # (142–202°) віддавали свої повні дуги так само.
    # Тепер рядок несе ПЕРЕТИН: палітра каже, ЯКІ сім'ї її, схема каже, ЯКУ дугу
    # тримає цей образ, і в пул іде те, що задовольняє обох. Сім'я, чий перетин
    # порожній, у фід не йде — як і доти. Нейтральні рядки не чіпаються: нейтраль
    # законна під будь-яку схему (те саме рішення, що в `pipeline.схема_образу`).
    _дуги = {с: v.get("дуга_тону") for с, v in (спец.get("слоти") or {}).items() if isinstance(v, dict)}
    # Дуги інших сімей схеми великих поверхонь (рядок 133): рядок палітри, що
    # перетинає будь-яку з них, лишається — у слоті живуть усі сім'ї схеми.
    _ще_дуги = {с: [tuple(д["дуга"]) for д in (v.get("дуги_схеми") or ())]
                for с, v in (спец.get("слоти") or {}).items() if isinstance(v, dict)}
    def _обрізати_усіма(r):
        """Рядки, обрізані КОЖНОЮ дугою схеми слота: власна дуга й дуги інших сімей
        схеми великих поверхонь (рядок 133). Слот без `дуги_схеми` — рівно
        `_обрізати`, тобто нуль або один рядок, як доти."""
        перший = _обрізати(r)
        вих = [перший] if перший else []
        if r.get("метал") or r.get("нейтраль") or r.get("h_from") is None or r.get("h_to") is None:
            return вих
        for д in _ще_дуги.get(r.get("слот")) or ():
            п = _перетин_дуг((float(r["h_from"]), float(r["h_to"])), (float(д[0]), float(д[1])))
            if п is not None:
                вих.append(dict(r, h_from=п[0], h_to=п[1], дуга_до_обрізання=(r["h_from"], r["h_to"])))
        return вих
    def _обрізати(r):
        """Рядок, обрізаний дугою схеми, або None — якщо схема його не тримає."""
        д = _дуги.get(r.get("слот"))
        # МЕТАЛ (K-PAL-11) ОБРІЗАННЮ НЕ ПІДЛЯГАЄ — з тієї самої причини, що й
        # нейтраль: золота застібка не є кольором образу, її судить температура
        # людини, а не дуга схеми. Обрізати її дугою означало б вимагати від
        # фурнітури бути в тоні тканини — правила такого нема в жодному джерелі.
        if r.get("метал"):
            return r
        if r.get("нейтраль") or r.get("h_from") is None or r.get("h_to") is None:
            return r
        if isinstance(д, (list, tuple)) and len(д) == 2 and д[0] is not None:
            п = _перетин_дуг((float(r["h_from"]), float(r["h_to"])), (float(д[0]), float(д[1])))
            if п is None:
                return None
            return dict(r, h_from=п[0], h_to=п[1], дуга_до_обрізання=(r["h_from"], r["h_to"]))
        if д == "нейтраль":
            return None
        return r
    for r in _PP.рядки_у_фід(спец):
        запити.extend(_обрізати_усіма(r))
    import palettes as _PL
    for r in _PL.рядки_у_фід(спец):
        запити.extend(_обрізати_усіма(r))
    # ── ОБРАНА ОСНОВА — ВІКНО, А НЕ РЕЧЕННЯ (19.09.2026) ─────────────────────
    # Рядок сім'ї обраної основи їде в добір НАРІВНІ з дугами схеми, а не під
    # ними: він додається ПІСЛЯ `_обрізати` навмисно. Обрізати вибір жінки дугою
    # схеми означало б, що система спершу просить її назвати колір, а тоді сама
    # вирішує, чи брати його до уваги, — і саме так виглядав вихід 19.09: пул
    # ЖОДНОЇ червоної речі при 1004 у каталозі.
    # ⚠ ТІЛЬКИ АКЦЕНТНІ СЛОТИ. «Акцент — це одна річ, а не весь образ»: під
    # «нейтрали+акцент» домінанта й секундант лишаються нейтральними, і кольорове
    # вікно на них зламало б саму схему, яку жінка обрала поруч із основою. Слот,
    # чия роль нейтральна (`сім_я` в полі) або вироджена (`попередження`), рядка
    # не дістає.
    # ЩО ЦЕ НЕ РОБИТЬ: не робить колір обов'язковим. Це рядок ДОБОРУ — він кладе
    # речі в пул; що з них узяти, вирішує модель, а чи виконано обіцянку схеми —
    # суд (`palettes.обіцянка_схеми`).
    _осн = спец.get("обрана_основа") or None
    # СХЕМА ВЕЛИКИХ ПОВЕРХОНЬ (рядок 133): основа — якір ДОМІНАНТИ (її дуга стоїть на
    # тоні основи), тож вікно сім'ї основи йде туди, а не на сумку, яку тепер несе
    # чужа сім'я; і межа кольору — та сама, що в сімей схеми (`МЕЖА_СІМ_Ї`).
    _великі = спец.get("поверхні") == "великі"
    _роль_осн = "домінанта" if _великі else "акцент"
    if _осн and _осн.get("дуга"):
        _дл, _дв = float(_осн["дуга"][0]), float(_осн["дуга"][1])
        for с, v in (спец.get("слоти") or {}).items():
            if not isinstance(v, dict) or v.get("роль") != _роль_осн: continue
            if v.get("попередження") or "сім_я" in v or not v.get("L"): continue
            _C_в = v.get("C") or (28.0, 70.0)
            _пів = max(8.0, (float(_C_в[1]) - float(_C_в[0])) / 2.0)
            _C_о_c = float(_осн["C"])
            _пор = МЕЖА_СІМ_Ї if _великі else поріг_кольору(_осн["h"], _осн["L"])
            _Cmin = max(_пор, _C_о_c - _пів)
            _Cmax = max(_Cmin + 1.0, _C_о_c + _пів)
            запити.append(dict(
                слот=с, L_min=float(v["L"][0]), L_max=float(v["L"][1]),
                C_min=round(_Cmin, 1), C_max=round(_Cmax, 1),
                h_from=_дл, h_to=_дв, нейтраль=False, спроба=0, ранг_риси=1,
                роль="обрана_основа:%s" % (_осн.get("сім_я") or "—"),
                обрана_основа=True, поріг_нейтралі=round(_пор, 1),
                джерело_тону="вибір людини: основа «%s»" % (_осн.get("база") or _осн["hex"]),
                чому=("жінка обрала основу %s (%s): %s. Вікно її сім'ї стоїть у доборі "
                      "нарівні з дугою схеми — обраний колір мусить бути ДОСЯЖНИМ у "
                      "слоті, якому схема дала роль %s"
                      % (_осн["hex"], _осн.get("насиченість") or "смуга не названа",
                         _осн.get("джерело") or "",
                         "домінанти" if _великі else "акценту"))))
    # НЕЙТРАЛЬ — ЦЕ АХРОМАТ АБО НЕЙТРАЛЬНА СІМ'Я КОРПУСУ, А НЕ «БУДЬ-ЯКИЙ ТОН ДО C 34»
    # (16.09.2026). Доти нейтральний рядок без меж тону з C_max = стелі схеми пускав у
    # пул під тональну приглушений рожевий, теплий бежевий і бірюзовий як «нейтралі»:
    # половина пулу стояла поза дугою. Рядок без тону і з C_max > 12 розкладається на
    # три: ахромат (C ≤ 12, тон будь-який), тепла нейтраль (45–115°, C ≤ 34) і холодна
    # (230–300°, C ≤ 24) — межі з `реєстр_правил.C` (K-COL-06).
    import реєстр_правил as _РЕЄСТР_
    _тепла = tuple(_РЕЄСТР_.C.get("warm_neutral") or (45., 115., 34.))
    _холодна = tuple(_РЕЄСТР_.C.get("cool_neutral") or (230., 300., 24.))
    _розкладені = []
    for r in запити:
        if r.get("нейтраль") and r.get("h_from") is None and float(r.get("C_max") or 0) > 12.0:
            _розкладені.append(dict(r, C_max=min(12.0, float(r.get("C_max") or 12.0)), роль=str(r.get("роль") or "") + ":ахромат"))
            _розкладені.append(dict(r, h_from=float(_тепла[0]), h_to=float(_тепла[1]), C_max=min(float(_тепла[2]), float(r.get("C_max") or _тепла[2])), роль=str(r.get("роль") or "") + ":тепла"))
            _розкладені.append(dict(r, h_from=float(_холодна[0]), h_to=float(_холодна[1]), C_max=min(float(_холодна[2]), float(r.get("C_max") or _холодна[2])), роль=str(r.get("роль") or "") + ":холодна"))
        else:
            _розкладені.append(r)
    запити[:] = _розкладені
    # ЗАПАСНА ХВИЛЯ ДЛЯ ГАРАНТІЇ СЛОТА (`спроба=1`, бере composer лише коли в дузі мало):
    # нейтралі у ВЛАСНІЙ смузі світлоти слота (палітрова смуга L може не перетинати
    # смугу слота: «низ» 30–39 проти 55–76, і слот лишався без жодної нейтралі) і
    # дуга схеми, розширена на ±30°.
    for с, v in (спец.get("слоти") or {}).items():
        if not isinstance(v, dict) or not v.get("L") or v.get("попередження"): continue
        д = v.get("дуга_тону")
        Llo, Lhi = float(v["L"][0]), float(v["L"][1])
        Cw = v.get("C") or (0.0, 34.0)
        запити.append(dict(слот=с, L_min=Llo, L_max=Lhi, C_min=0.0, C_max=12.0, h_from=None, h_to=None, нейтраль=True, спроба=1, роль="нейтраль_запас:ахромат", джерело_тону="гарантія слота", чому="запас: ахромат у смузі світлоти слота"))
        запити.append(dict(слот=с, L_min=Llo, L_max=Lhi, C_min=0.0, C_max=float(_тепла[2]), h_from=float(_тепла[0]), h_to=float(_тепла[1]), нейтраль=True, спроба=1, роль="нейтраль_запас:тепла", джерело_тону="гарантія слота", чому="запас: тепла нейтраль у смузі слота"))
        запити.append(dict(слот=с, L_min=Llo, L_max=Lhi, C_min=0.0, C_max=float(_холодна[2]), h_from=float(_холодна[0]), h_to=float(_холодна[1]), нейтраль=True, спроба=1, роль="нейтраль_запас:холодна", джерело_тону="гарантія слота", чому="запас: холодна нейтраль у смузі слота"))
        if isinstance(д, (list, tuple)) and len(д) == 2 and д[0] is not None:
            запити.append(dict(слот=с, L_min=Llo, L_max=Lhi, C_min=float(Cw[0]), C_max=float(Cw[1]), h_from=(float(д[0]) - 30.0) % 360, h_to=(float(д[1]) + 30.0) % 360, нейтраль=False, спроба=1, роль="дуга_запас", джерело_тону="гарантія слота", чому="запас: дуга схеми, розширена на 30° з кожного боку"))
    # ── K-MUA-01 НА ВЕСЬ СЛОТ, А НЕ НА ОДИН РЯДОК ────────────────────────────
    # Прохід стоїть ПІСЛЯ того, як зібрані ВСІ рядки (схемні, ехо, якірні, від рис,
    # з персональної та практикової палітр): вікна слота — диз'юнкція, тож дірка,
    # поставлена на одному рядку, витікає через сусідній.
    # НЕЙТРАЛЬНІ РЯДКИ ТЕЖ ДІСТАЮТЬ КУЛЮ, і це відхилення від початкового плану
    # правки, зроблене ВИМІРОМ, а не смаком. План казав нейтральні пропустити, бо
    # «нейтраль(lab) і так відсіює хроматичну помаду». На приймальному кольорі
    # #a9736b (C*24.1 при стелі нейтралі 24.0) це неправда: помада стоїть РІВНО на
    # межі коридору теплої нейтралі, і 17 точок дірки проходили саме нейтральними
    # рядками «верх» від персональної та практикової палітр. Приглушена помада —
    # не рідкість, тож виняток лишав дірку напіввідчиненою рівно для того класу
    # кольорів, проти якого правило й стоїть.
    # Для насиченої помади куля на нейтральному рядку інертна (жодна нейтраль не
    # лежить ближче за ΔE00 5 до хроматичного кольору) — отже це строго сильніше,
    # а не ширше.
    кулі_слота = _кулі_слотів(спец)
    if кулі_слота:
        for r in запити:
            кулі = кулі_слота.get(r.get("слот"))
            if кулі: r.setdefault("не_ближче_за", []).extend(кулі)
    # ── ЧЕРГА СПРОБ — ПОЛЕ РЯДКА, А НЕ ЗНАННЯ СПОЖИВАЧА ─────────────────────
    # Рядки від рис, з персональної та практикової палітр — усі основні (спроба 0).
    # Запасні лише два види, і вони позначені там, де народжуються: якірна нейтраль
    # і принт-ехо. Дефолт стоїть тут, щоб жоден рядок не пішов у фід без черги.
    for r in запити:
        r.setdefault("спроба", 0)
    # ── R-COL-16: БІК b* ЇДЕ НА КОЖНОМУ ХРОМАТИЧНОМУ РЯДКУ (19.09.2026) ──────
    # Нейтральні рядки вже несуть своє b-вікно (`нейтраль_темп`, K-COL-06-T);
    # металеві судить температура людини (K-PAL-11). Хроматичному рядку вікно по
    # b* не ставиться (сила hint — не фільтр), а ставиться БІК, який composer
    # читає як другорядний член ключа сорту. Один свідок на одне питання:
    # бік рахує `бік_b_проти_людини` у `специфікація`, тут — лише доставка.
    # ЛИШЕ ПРИОБЛИЧЧЕВІ СЛОТИ (той самий поріг, що в суді — `NEAR_МІН`): корпус
    # міряв одяг ПРОТИ ОБЛИЧЧЯ; на взутті чи низі вісь b* проти очей нічого не
    # стверджує, і бік там лише крутив би нічиї в далеких слотах без підстави.
    _бб = (спец.get("бік_b") or {}) if isinstance(спец, dict) else {}
    if _бб.get("вхід"):
        for r in запити:
            if r.get("нейтраль") or r.get("метал"): continue
            if _КОЛІР.SLOT_NEAR_FALLBACK.get(r.get("слот"), 0.2) < _КОЛІР.NEAR_МІН: continue
            r["b_бік"] = int(_бб["бік"])
            r["b_бік_джерело"] = "R-COL-16: b* очей %.1f" % float(_бб.get("b_очей") or 0.0)
    # Стабільне сортування: рядки з рангом риси — за рангом; рядки без рангу (схемні,
    # якірні) лишаються попереду у своєму порядку. Черга рядків = черга спроб retrieval.
    запити.sort(key=lambda q: q.get("ранг_риси", 0) if isinstance(q, dict) else 0)
    return запити
