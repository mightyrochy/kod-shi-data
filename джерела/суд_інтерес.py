# ── K-CRA-04 × K-INT-04: КРОК РЕДАГУВАННЯ, ОБМЕЖЕНИЙ ПІДЛОГОЮ ІНТЕРЕСУ ─────
# K-CRA-04 (C·strong): після збирання видалити елемент, чиє видалення НЕ ЗНИЖУЄ жодну
# метрику («зніми один аксесуар» — апокриф Шанель, принцип канонічний).
# K-INT-04 (архітектурне·hard): крок редагування НЕ МАЄ ПРАВА зрізати образ нижче
# підлоги інтересу; конфлікт «перевантажено, але видалення оголить» розв'язується
# ЗАМІНОЮ джерела інтересу на тихіше, НЕ видаленням у нуль.
#
# ЧОМУ ЦІ ДВА РАЗОМ І НЕ ПОРІЗНО: K-INT-04 не є самостійним правилом — це ОБМЕЖЕННЯ на
# K-CRA-04. Реалізувати перше без другого означало б дати кроку редагування різати до
# нуля; реалізувати друге без першого — обмежувати те, чого нема. Тому одна функція.
#
# ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after):
#   before — композитор збирає образ і віддає як є. Елемент, що не додає нічого
#            (третій срібний аксесуар при двох срібних), лишається, бо жодне правило
#            не питає «а чи стало б гірше без нього».
#   after   — кожен знімний елемент пробується на видалення; якщо жодна метрика не
#            падає, він позначений як зайвий. Якщо падає ІНТЕРЕС нижче підлоги —
#            видалення заборонене, і замість нього пропонується тихіша заміна.
#
# ⚠ ЩО ТУТ ФОЛЬКЛОРНЕ: «зніми один аксесуар» корпус сам називає апокрифом Шанель.
# Канонічний тут ПРИНЦИП (перевірити елемент на необхідність), а не число «один».
# Тому функція не знімає рівно один — вона повертає ВСІ зайві, і рішення за шаром вище.
ЗНІМНІ_СЛОТИ = ("прикраси", "шарф", "пояс", "сумка", "головний_убір", "верхній_шар")
ПІДЛОГА_ІНТЕРЕСУ = REGISTRY["підлога_інтересу"]["val"]   # K-INT-04 (T3, §23 теми-3): скільки джерел інтересу образ мусить зберегти.
                            # T3 · конвенція. Корпус дає ПІДЛОГУ як поняття, не число.
ІНТЕРЕС_C_МІН = REGISTRY["інтерес_c_мін"]["val"]   # T3: хрома, з якої річ читається як КОЛІР, а не як нейтраль.
                            # T3 · збігається з коридором нейтралей K-COL-06.

def джерела_інтересу(E):
    """Скільки в образі ДЖЕРЕЛ ВІЗУАЛЬНОГО ІНТЕРЕСУ (не скільки речей).

    ВИПРАВЛЕНО ПІСЛЯ ПРОБИ: перша версія рахувала будь-яку річ з площею ≥5%, і
    підлога інтересу не спрацьовувала НІКОЛИ — блуза плюс штани вже давали «інтерес 2»
    при підлозі 1, хоч обидві могли бути гладкими нейтралями. Тобто K-INT-04 був
    формально реалізований і фактично мертвий: він не міг заборонити жодного
    видалення. Нейтральна база — це ВІДСУТНІСТЬ інтересу, а не його джерело.

    Джерелом рахується річ, що несе: хрому ≥ ІНТЕРЕС_C_МІН, або принт/візерунок, або
    виразну фактуру. Кожне — окремий важіль, яким можна «стишити» річ (K-INT-04
    вимагає саме заміни на тихіше, тож перелік важелів мусить бути явним)."""
    дж = []
    for e in одна_на_річ(E):
        if (e.get("площа") or 0) < 0.03: continue
        чому = []
        lab = e.get("lab")
        if lab:
            C = lch(tuple(lab))[1]
            if C >= ІНТЕРЕС_C_МІН and not e.get("нейтраль"):
                чому.append("хрома C*%.0f" % C)
        if e.get("візерунок") and str(e["візерунок"]).lower() not in ("", "solid", "однотон"):
            чому.append("принт «%s»" % e["візерунок"])
        if str(e.get("текстура") or "").lower() in ("knit-chunky", "tweed-boucle",
                                                    "smooth-shine", "satin", "patent"):
            чому.append("фактура «%s»" % e["текстура"])
        # R-PRN-07 (strong): розміщений мотив — СТВОРЕНИЙ фокус, витрачає бюджет
        # фокусу, навіть якщо клас мотиву не читається («вишивка на кишені» — не
        # клас, а розміщення). Вхід зʼявився на укр. каталозі 27.08.2026 (3 SKU).
        _рм = e.get("розміщення_мотиву")
        if isinstance(_рм, dict) and _рм.get("вид") == "placed":
            чому.append("розміщений мотив (%s) на зоні «%s»" % (_рм.get("за_чим"), _рм.get("зона")))
            # П.14: `trace` — модуль ядра, `запис` тотальний (додає словник у
            # список); впасти могла тільки `%`-підстановка рядком вище, тобто
            # помилка коду. Летить у `bridge.виклик` → `помилка` + `код`.
            import trace as _СЛ
            _СЛ.запис("R-PRN-07", "розміщений мотив = створений фокус", "джерела_інтересу",
                      значення="%s → зона «%s»" % (_рм.get("за_чим"), _рм.get("зона")),
                      сила=None, напрям="джерело інтересу +1")
        if чому:
            дж.append(dict(річ=e.get("річ") or e.get("id"), слот=e.get("слот"),
                           важелі=чому))
    return дж

def _метрики_образу(E, темп_c=None, опади=None, вітер=None, речі=None,
                    стан=None, **kw):
    """⚠ `стан` — ІМЕНОВАНИЙ параметр, а не ключ у `**kw`, і це не стиль.
    07.09.2026 його додали через `**kw`, і він протік крізь цю функцію у
    `формальність_образу`, яка `**kw` не приймає: TypeError валив увесь
    `перевірити_образ`, а гейт досяжності впав із 44 % до 17 %. Рівно той клас,
    що й ручні білі списки: ключ їде далі, ніж його вміють прийняти. Іменований
    параметр робить межу видимою в сигнатурі."""
    """Скалярні метрики, за якими міряється «стало гірше». Тільки ті, що вже
    рахуються — нових метрик крок редагування не вигадує.

    ТЕПЛО ВХОДИТЬ У МЕТРИКИ (28.08.2026). Доти крок бачив лише когерентність нейтралей
    і формальність, тож при 6 °C «пальто можна зняти — жодна метрика не падає» було
    правдою за побудовою: тепла серед метрик не було. `погода()` уже рахує шари проти
    температури (K-WEA-01) і мовчить без темп_c, тому вона й береться — без вигадок."""
    зн = (нейтралі_крос(E) or []) + (формальність_образу(E, **kw) or [])
    if темп_c is not None:
        # шари рахуються З РЕЧЕЙ (погода(): «тепло — не питання видимості»); без
        # `речі` лічба падала на видимі елементи, і в стані «надворі» верх під
        # застібнутим пальтом не рахувався — «шарів замало» і з пальтом, і без,
        # тож пальто виходило «можна зняти» при +6 °C (спіймано гейтом §37 28.08)
        # СТАН ПЕРЕДАЄТЬСЯ (07.09.2026): без нього BREAKS правила K-MAT-03
        # («climate-controlled interiors») тут не діяв, і крок редагування рахував
        # сезонну семантику тканини навіть тоді, коли решта системи її утримує.
        # Дві половини одного правила давали різну відповідь у двох місцях.
        зн += (погода(E, темп_c=темп_c, опади=опади, вітер=вітер, речі=речі,
                      стан=стан) or [])
    return dict(
        знахідок=len(зн),
        вага_знахідок=round(sum(z.get("сила_нп") or 0.0 for z in зн), 3),
        інтерес=len(джерела_інтересу(E)),
        слотів=len(одна_на_річ(E)))

# R-CHEV-11 — дубль `суд_образу.підлога_інтересу_проактивно`: «тьмяно й нічим не оживлено».
def підлога_інтересу_проактивно(E, intent="conventional", тихо=False):
    """K-INT-04 ПРОАКТИВНО (тема-4 XII.2 B1): скільки джерел інтересу образ МУСИТЬ нести
    за наміром — comfort/conventional/context ≥ 1, fashion_forward ≥ 2 (усі числа T3,
    фольклорні). Перенесено з composer._оцінити 24.08.2026: там підлога діяла лише під
    час ВИБОРУ, а ЗІБРАНИЙ образ із трьох нейтралей проходив review без жодного слова —
    гейт досяжності звітував гілку мертвою («три нейтралі — K-INT-04»).

    `тихо` — пул зібрано в траурному регістрі (рядок 154, мітка `траур_пулу` пакета):
    ремонт лише фактурою, без «АБО акцентний колір або принт» біля обличчя."""
    дж = джерела_інтересу(E)
    # ПІДЛОГА — З ЛЕКСИКОНУ НАМІРУ (K-PER-00, 19.09.2026): доти «2» стояла тут
    # літералом під fashion_forward; comfort_first і context_optimal читають 1.
    мін = int(_намір(intent)["підлога"])
    if len(дж) >= мін:
        return []
    речі = [e.get("річ") or e.get("id") for e in одна_на_річ(E)]
    # ── K-COMP-06: У СТРИМАНОМУ КОНТЕКСТІ ФАКТУРА ЙДЕ ПЕРШОЮ ─────────────────
    # ЩО ТУТ СТОЯЛО І ЧОМУ ЦЕ БУЛО ГІРШЕ ЗА МОВЧАННЯ. Ремонт перелічував
    # «акцентний колір, принт або виразну фактуру» — саме в цьому порядку, —
    # і в дужках ЦИТУВАВ K-COMP-06 словами «у стриманому контексті спершу
    # фактура, не колір». Тобто те саме речення називало правило й робило
    # протилежне до того, що воно каже. У зведенні K-COMP-06 стояло «без сліду»,
    # і це було правдою навіть там, де його ім'я стояло в тексті.
    # ЩО КАЖЕ КОРПУС (тема-4, CHANGES, дослівно): «when the interest floor is
    # unmet in a conservative context, the system reaches for texture first, not
    # colour». Умова — стриманий намір; він тут уже порахований (`мін` вище
    # береться з того самого `_канон_намір`).
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ, І НЕ ЛИШЕ В ТЕКСТІ: разом із порядком міняється
    # ЗАПИТ У КАТАЛОГ. Доти він завжди просив хрому (`хрома_від`) — тобто шар
    # retrieval діставав вимогу кольору навіть там, де корпус просить фактури, і
    # правило не могло вплинути на добір пулу навіть у принципі. Тепер у
    # стриманому контексті запит іде по фактурі, і K-COMP-06 діє в першому з
    # трьох місць — у доборі, а не лише в реченні.
    # ── ТРАУРНИЙ ПУЛ: ФАКТУРА — ЄДИНИЙ РЕМОНТ (рядок 154) ───────────────────
    # Похорон — стриманий контекст за визначенням, хай який намір, тож фактура йде
    # першою й тут. Друге «АБО акцентний колір або принт біля обличчя» — рівно те,
    # чого K-OCC-01 на похороні не просить («no bright… no shine near the face»), і
    # пул рук 1–2 таких речей уже не має (`траурний_регістр.траурне_відсічення`):
    # порада кликала модель по річ, якої нема. ВИМІРЯНО (`проби/traur_154.py`: 3 траурні
    # сценарії × 10 образів): K-INT-04 — на 6 образах кожного, і всі 6 ремонтів із цим
    # «АБО»; на стенді (похорон, сіди 3/5/7) — рука 1 усіх трьох сідів.
    _стримано = тихо or _канон_намір(intent) not in ("fashion_forward", "statement", "editorial")
    _колір_ремонт = ("акцентний колір або принт у слоті, найближчому до обличчя")
    _фактура_ремонт = ("виразна фактура в слоті, найближчому до обличчя — у стриманому "
                       "контексті вона додає інтересу, не додаючи другого колірного "
                       "чи мотивного фокусу (K-COMP-06)")
    return [dict(_зн(
        "K-INT-04", "soft",
        "в образі %d джерел інтересу при підлозі %d" % (len(дж), мін),
        речі,
        "жодна річ не несе ні хроми ≥%.0f, ні принту, ні виразної фактури — образ "
        "складається лише з нейтралей. Підлога інтересу діє й на ЗІБРАНОМУ образі, не "
        "лише під час вибору" % ІНТЕРЕС_C_МІН,
        ремонт=(_фактура_ремонт if тихо          # один ремонт — рядком: «як варіант — …»
                else [_фактура_ремонт, "АБО " + _колір_ремонт] if _стримано
                else [_колір_ремонт, "АБО " + _фактура_ремонт]),
        запит=(dict(слот=None, фактура="виразна", чому="K-COMP-06: у стриманому "
                    "контексті інтерес підіймається фактурою, не другим кольором")
               if _стримано else
               dict(слот=None, хрома_від=ІНТЕРЕС_C_МІН,
                    чому="K-INT-04: підлога інтересу, проактивно")),
        ламається="підлога = %d і поріг хроми %.0f — КОНВЕНЦІЇ (T3). Мінімалістичний "
                  "образ із нейтралей може бути свідомим вибором — тому soft, не гейт. "
                  "І межа самого K-COMP-06, названа ним же: фактурний контраст на "
                  "фотографії й здалеку майже зникає (K-CRA-10), а наш рендер і Є "
                  "фотографія — тобто порада працює в житті сильніше, ніж у показі"
                  % (мін, ІНТЕРЕС_C_МІН),
        поріг=float(мін), вимір=float(len(дж)), повна=float(мін + 1)),
        також_правила=(["K-COMP-06"] if _стримано else None),
        сила_нп_джерело="вимір (власний: брак джерел до підлоги)")]
def крок_редагування(E, темп_c=None, опади=None, вітер=None, речі=None,
                     стан=None, **kw):
    """K-CRA-04 × K-INT-04. (зайві, заборонені_до_видалення, база).
    `темп_c/опади/вітер` — щоб видалення шару, який гріє, рахувалось погіршенням;
    `речі` — щоб шари рахувались із речей (светр під застібнутим пальтом гріє).

    `зайві` — елементи, чиє видалення не погіршує ЖОДНОЇ метрики.
    `заборонені` — ті, чиє видалення прибрало б інтерес нижче підлоги: для них
    ремонт — ЗАМІНА на тихіше джерело, не видалення."""
    # ── БАЗА Й КАНДИДАТ МІРЯЮТЬСЯ ОДНІЄЮ ЛІНІЙКОЮ (08.09.2026) ───────────────
    # ЩО ТУТ СТОЯЛО: база рахувалась БЕЗ `стан`. `стан` — іменований параметр цієї
    # функції, тож у `**kw` він фізично не потрапляє, а кандидат нижче дістає його
    # явно (`стан=стан`). Наслідок: база завжди мірялась «надворі»
    # (`погода`: `надворі = (стан != "у_приміщенні")` → True при None), а кандидат —
    # у стані виклику. `pipeline` кличе саме з `стан="у_приміщенні"`.
    #
    # Виміряно 08.09.2026 на образі «верх + низ + замшеві черевики + шарф», −10 °C, дощ:
    #     стан=None            → знахідок 2, вага 2.00     ← так мірялась БАЗА
    #     стан="у_приміщенні"  → знахідок 1, вага 1.00     ← так мірявся КАНДИДАТ
    # Тест «гірше» через це систематично зсунутий у бік «зняти можна», і на цьому
    # самому вході K-CRA-04 радив: «шарф можна зняти — жодна метрика не падає».
    # Що справді стається без шарфа при −10 °C: K-WEA-01 «шарів замало» силою 1.0
    # і «нижче −8 °C палітру несуть шапка-шарф-рукавиці» силою 0.6. Тобто це була
    # порада людині зняти шарф у мороз.
    #
    # Пояснення знахідки себе й видавало: «вага 1.60 (було 2.00)» — вага впала ВІД
    # ВИДАЛЕННЯ речі, що при симетричному вимірі неможливе.
    база = _метрики_образу(E, темп_c=темп_c, опади=опади, вітер=вітер, речі=речі,
                           стан=стан, **kw)
    зайві, заборонені = [], []
    for e in одна_на_річ(E):
        if e.get("слот") not in ЗНІМНІ_СЛОТИ: continue
        без = [x for x in E if (x.get("річ") or x.get("id")) != (e.get("річ") or e.get("id"))]
        _ключ_e = (e.get("річ") or e.get("id"))
        без_речей = [р for р in (речі or []) if (р.get("назва") or р.get("id")) != _ключ_e and р.get("id") != _ключ_e] if речі else None
        м = _метрики_образу(без, темп_c=темп_c, опади=опади, вітер=вітер, речі=без_речей,
                            стан=стан, **kw)
        гірше = (м["знахідок"] > база["знахідок"]
                 or м["вага_знахідок"] > база["вага_знахідок"] + 1e-9)
        if гірше: continue
        # «оголить» — лише коли видалення ПЕРЕВОДИТЬ образ під підлогу. Образ, який
        # уже під підлогою (база < підлоги), річ не тримає: її видалення нічого не
        # оголює, і про порожнечу вже каже підлога_інтересу_проактивно. Спіймано
        # 28.08.2026 (холодна-темна · прогулянка): «сумка тримає образ» і «в образі
        # 0 джерел інтересу» стояли в ОДНІЙ знахідковій стрічці одного образу.
        if м["інтерес"] < ПІДЛОГА_ІНТЕРЕСУ and база["інтерес"] >= ПІДЛОГА_ІНТЕРЕСУ:
            заборонені.append(dict(_зн(
                "K-INT-04", "hard",
                "«%s» зайвий за метриками, але його видалення оголить образ"
                % (e.get("річ") or e.get("id")),
                [e.get("річ") or e.get("id")],
                "видалення не погіршує жодної метрики, АЛЕ лишає %d джерел інтересу "
                "при підлозі %d. K-CRA-04 не має права різати нижче підлоги: конфлікт "
                "«перевантажено, але видалення оголить» розв'язується ЗАМІНОЮ джерела "
                "на тихіше, не видаленням у нуль"
                % (м["інтерес"], ПІДЛОГА_ІНТЕРЕСУ),
                ремонт=["замінити «%s» на тихіше джерело інтересу того самого слота — "
                        "менша маса, нижча хрома, дрібніший масштаб"
                        % (e.get("річ") or e.get("id"))],
                запит=dict(слот=e.get("слот"), замість=e.get("річ"),
                           тихіше=True, чому="K-INT-04: підлога інтересу"),
                ламається="підлога = %d — конвенція (T3). Корпус дає ПОНЯТТЯ підлоги, "
                          "не число; калібрується на вердиктах носіння" % ПІДЛОГА_ІНТЕРЕСУ,
                поріг=float(ПІДЛОГА_ІНТЕРЕСУ), вимір=float(м["інтерес"])),
                # ТРИМАЄ, НЕ ТИСНЕ (28.08.2026, каталог_повний, 6 сцен × 200 комбінацій).
                # Це ЗАБОРОНА ВИДАЛЕННЯ — річ несе образ, а не псує його. Із силою 1.0 вона
                # їхала в граф як напруга на сумці: «сумка» була вузьким місцем у 135–145
                # комбінаціях із 200, O4 пропонував замінити САМЕ те, що правило велить
                # берегти, а ключ композитора штрафував образ за інтерес рівно на підлозі —
                # тобто перевагу «≥ 2 джерел», якої корпус не дає (підлога = 1, T3).
                регістр="репліка", сила_нп=0.0, тримає=True,
                сила_нп_джерело="архітектурне обмеження: тримає слот, напруги не несе"))
            continue
        зайві.append(dict(_зн(
            "K-CRA-04", "soft",
            "«%s» можна зняти — жодна метрика не падає" % (e.get("річ") or e.get("id")),
            [e.get("річ") or e.get("id")],
            "без нього: знахідок %d (було %d), вага %.2f (було %.2f), інтерес %d "
            "(підлога %d). Тобто елемент не несе роботи"
            % (м["знахідок"], база["знахідок"], м["вага_знахідок"],
               база["вага_знахідок"], м["інтерес"], ПІДЛОГА_ІНТЕРЕСУ),
            ремонт=["зняти «%s»" % (e.get("річ") or e.get("id"))],
            ламається="метрики тут — лише ті, що вже рахує система (когерентність "
                      "нейтралей, формальність, лік джерел інтересу). Елемент може "
                      "нести роботу, якої система НЕ МІРЯЄ: сентиментальну, тактильну, "
                      "функціональну. «Зніми один аксесуар» корпус сам називає "
                      "апокрифом Шанель — канонічний ПРИНЦИП, не число",
            поріг=0.0, вимір=round(база["вага_знахідок"] - м["вага_знахідок"], 3),
            повна=1.0),
            сила_нп_джерело="вимір (власний: приріст ваги знахідок від видалення)"))
    return зайві, заборонені, база
