# ── K-CRA-04 × K-INT-04: КРОК РЕДАГУВАННЯ, ОБМЕЖЕНИЙ ПІДЛОГОЮ ІНТЕРЕСУ ─────
# K-CRA-04 (C·strong): після збирання видалити елемент, чиє видалення НЕ ЗНИЖУЄ жодну
# метрику («зніми один аксесуар» — апокриф Шанель, принцип канонічний).
# K-INT-04 (архітектурне·hard): крок редагування НЕ МАЄ ПРАВА зрізати образ нижче
# підлоги інтересу; конфлікт «перевантажено, але видалення оголить» розв'язується
# ЗАМІНОЮ джерела інтересу на тихіше, НЕ видаленням у нуль.
#
# ЧОМУ ЦІ ДВА РАЗОМ І НЕ ПОРІЗНО: K-INT-04 не є самостійним правилом — це ОБМЕЖЕННЯ на
# K-CRA-04. Реалізувати перше без другого означало б дати кроку редагування різати до
# нуля; реалізувати друге без першого — обмежувати те, чого нема. Тому одна функція.
#
# ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after):
#   before — композитор збирає образ і віддає як є. Елемент, що не додає нічого
#            (третій срібний аксесуар при двох срібних), лишається, бо жодне правило
#            не питає «а чи стало б гірше без нього».
#   after   — кожен знімний елемент пробується на видалення; якщо жодна метрика не
#            падає, він позначений як зайвий. Якщо падає ІНТЕРЕС нижче підлоги —
#            видалення заборонене, і замість нього пропонується тихіша заміна.
#
# ⚠ ЩО ТУТ ФОЛЬКЛОРНЕ: «зніми один аксесуар» корпус сам називає апокрифом Шанель.
# Канонічний тут ПРИНЦИП (перевірити елемент на необхідність), а не число «один».
# Тому функція не знімає рівно один — вона повертає ВСІ зайві, і рішення за шаром вище.
ЗНІМНІ_СЛОТИ = ("прикраси", "шарф", "пояс", "сумка", "головний_убір", "верхній_шар")
ПІДЛОГА_ІНТЕРЕСУ = REGISTRY["підлога_інтересу"]["val"]   # K-INT-04 (T3, §23 теми-3): скільки джерел інтересу образ мусить зберегти.
                            # T3 · конвенція. Корпус дає ПІДЛОГУ як поняття, не число.
ІНТЕРЕС_C_МІН = REGISTRY["інтерес_c_мін"]["val"]   # T3: хрома, з якої річ читається як КОЛІР, а не як нейтраль.
                            # T3 · збігається з коридором нейтралей K-COL-06.

def джерела_інтересу(E):
    """Скільки в образі ДЖЕРЕЛ ВІЗУАЛЬНОГО ІНТЕРЕСУ (не скільки речей).

    ВИПРАВЛЕНО ПІСЛЯ ПРОБИ: перша версія рахувала будь-яку річ з площею ≥5%, і
    підлога інтересу не спрацьовувала НІКОЛИ — блуза плюс штани вже давали «інтерес 2»
    при підлозі 1, хоч обидві могли бути гладкими нейтралями. Тобто K-INT-04 був
    формально реалізований і фактично мертвий: він не міг заборонити жодного
    видалення. Нейтральна база — це ВІДСУТНІСТЬ інтересу, а не його джерело.

    Джерелом рахується річ, що несе: хрому ≥ ІНТЕРЕС_C_МІН, або принт/візерунок, або
    виразну фактуру. Кожне — окремий важіль, яким можна «стишити» річ (K-INT-04
    вимагає саме заміни на тихіше, тож перелік важелів мусить бути явним)."""
    дж = []
    for e in одна_на_річ(E):
        if (e.get("площа") or 0) < 0.03: continue
        чому = _важелі_інтересу(e)
        if чому:
            дж.append(dict(річ=e.get("річ") or e.get("id"), слот=e.get("слот"),
                           важелі=чому))
    return дж


# ── ХРОМА ІНТЕРЕСУ РЕЧІ-ВІКНА — ДВОБІЧНО (КОЛІР-ВІКНО-СУД, рядок 3081) ──────────
# ЩО БУЛО. Важіль «хрома» рахувався з C* точки, а для кольору зі слова це центр вікна: «синій»
# (центр C* 46, вікно від нейві-нейтралі) ніс інтерес за побудовою, «бежевий» — ні, хоч вікно сягає
# кемелу. На каталозі пакета 1 307 з 1 838 речей-слів лежать по обидва боки `інтерес_c_мін`.
# Двозначна заміна хибна в один із боків (спроба 2б: K-CRA-02 тихне). ЩО СТАЛО. Тризначно:
# «так» — уся хрома вікна над порогом і жодна точка не нейтраль, «ні» — навпаки, «невідомо» —
# важелем не рахується, але K-INT-04 і K-CRA-02 на ньому вироку не роблять: «без входу» з полем
# `колір_не_вимір` (п.4). Вимір — точкою, як доти.
def хрома_інтересу(e):
    """«так» / «невідомо» / «ні»: чи колір речі чи елемента несе інтерес хромою
    (C* ≥ `ІНТЕРЕС_C_МІН` і не нейтраль K-COL-06). Вимір — точкою з полем `нейтраль` елемента,
    як доти; вікно слова — `колір_річ.гучність_меж` з порогом інтересу і `нейтраль_меж`."""
    import колір_річ as _КР
    lab = e.get("lab")
    if _КР.не_вимір(e) is None:
        return "так" if lab and lch(tuple(lab))[1] >= ІНТЕРЕС_C_МІН and not e.get("нейтраль") else "ні"
    г = _КР.гучність_меж(e, поріг=ІНТЕРЕС_C_МІН)
    if г is None:
        return "ні"
    return _КР._і({"так": "так", "ні": "ні"}.get(г, "невідомо"), _КР._не(_КР.нейтраль_меж(e) or "так"))


def можливий_інтерес(e):
    """Річ, чий єдиний можливий важіль — хрома вікна слова «невідомо» (`хрома_інтересу`)."""
    return хрома_інтересу(e) == "невідомо" and not _важелі_інтересу(e)


def _важелі_інтересу(e):
    """Чим САМЕ ця поверхня цікава: перелік важелів, порожній — нічим.

    Винесено з `джерела_інтересу` (Н-2, 28.09.2026), щоб критерій «річ несе інтерес»
    стояв в ОДНОМУ місці: його питає ще й `річ_несе_інтерес` нижче. Тіло перенесено
    байт у байт, разом із лозою R-PRN-07."""
    чому = []
    if хрома_інтересу(e) == "так":                    # вікно слова — нижньою межею хроми
        import колір_річ as _КР
        чому.append("хрома C*%.0f" % _КР.межі_кольору(e)[2])
    if e.get("візерунок") and str(e["візерунок"]).lower() not in ("", "solid", "однотон"):
        чому.append("принт «%s»" % e["візерунок"])
    # SILK-SHINE — ГУЧНА ФАКТУРА (рядок 2520). Тут стояв лише `smooth-shine`, якого в каталозі
    # 0 речей, а `silk-shine` (231: шовк, металік, атлас-подібне) не рахувався: одна шовкова чи
    # металева сукня не була джерелом інтересу, хоч `КЛАС_ПОВЕРХНІ` нижче й зводить її до «блиску»
    # поруч із satin і patent. Доти її рятував i1 зі шкіряним взуттям; після рядка 2450 B1 падав
    # на нетраурних образах, де єдиним джерелом був шовк (`проби/i1_2450.py`). На траурі блиск
    # гасить K-OCC-01 ще в пулі (`траурний_регістр`), тож тут виняток не потрібен.
    if str(e.get("текстура") or "").lower() in ("knit-chunky", "tweed-boucle",
                                                "smooth-shine", "silk-shine", "satin", "patent"):
        чому.append("фактура «%s»" % e["текстура"])
    # R-PRN-07 (strong): розміщений мотив — СТВОРЕНИЙ фокус, витрачає бюджет
    # фокусу, навіть якщо клас мотиву не читається («вишивка на кишені» — не
    # клас, а розміщення). Вхід зʼявився на укр. каталозі 27.08.2026 (3 SKU).
    _рм = e.get("розміщення_мотиву")
    if isinstance(_рм, dict) and _рм.get("вид") == "placed":
        чому.append("розміщений мотив (%s) на зоні «%s»" % (_рм.get("за_чим"), _рм.get("зона")))
        # П.14: `trace` — модуль ядра, `запис` тотальний (додає словник у
        # список); впасти могла тільки `%`-підстановка рядком вище, тобто
        # помилка коду. Летить у `bridge.виклик` → `помилка` + `код`.
        import trace as _СЛ
        _СЛ.запис("R-PRN-07", "розміщений мотив = створений фокус", "джерела_інтересу",
                  значення="%s → зона «%s»" % (_рм.get("за_чим"), _рм.get("зона")),
                  сила=None, напрям="джерело інтересу +1")
    return чому


# ── ПОВЕРХНЯ РЕЧІ: ФАКТУРА, А БЕЗ НЕЇ — МАТЕРІАЛ (рядок 1680) ─────────────────
# B4 корпусу — «texture OR MATERIAL carries something the colour does not» (тема-4 XII.2), а
# i1 — «texture contrast» (XII.3). Код читав лише `текстура`, а її нема на 8 811 з 11 828
# записів каталогу; `волокно` (нормалізований код складу, `verify.волокно_зі_слова`) є на
# 10 508. Тож поверхня — `текстура`, коли вона є, інакше `волокно`; None — ні того, ні того,
# тобто вхід невідомий, а не «та сама поверхня». Волокно, яке фід сам зводить до класу
# фактури (`verify.СЛОВО_ТКАНИНИ`: шкір/замш → leather, атлас/сатин → satin…), зводиться до
# того самого класу: інакше шкіряні туфлі з `текстура` і шкіряна сумка лише з `волокно`
# рахувались би двома різними поверхнями.
ВОЛОКНО_ЯК_ФАКТУРА = {"шкіра": "leather", "екошкіра": "leather", "замша": "leather",
                      "нубук": "leather", "лак": "patent", "атлас": "satin", "сатин": "satin",
                      "шовк": "silk-shine", "твід": "tweed-boucle", "букле": "tweed-boucle",
                      "денім": "denim"}


def поверхня_речі(e):
    """Код поверхні речі для B4 і i1: `текстура`, інакше `волокно` (зведене до класу фактури,
    де фід його так зводить); None — поверхня невідома (вхід, а не «та сама»)."""
    т = e.get("текстура")
    if т:
        return str(т)
    в = e.get("волокно")
    return ВОЛОКНО_ЯК_ФАКТУРА.get(str(в), str(в)) if в else None


# ── ТИХІ ДЖЕРЕЛА НА ТРАУРІ: i1 І i2 (рядок 1680) ─────────────────────────────
# Корпус, тема-4 XIV.1 крок 9: «meet the floor for the declared intent; in conservative
# contexts prefer quiet sources (i1/i2/i4)». `джерела_інтересу` рахує хрому, принт, гучні
# класи фактури й розміщений мотив — на траурі K-OCC-01 гасить перші й блиск, і тихих джерел
# не лишалось: підлога K-INT-04 стояла на 261 з 312 траурних образів рук 1–2 збережених
# прогонів. Тепер у траурному пулі (`тихо`) рахуються ще два тихі джерела, на які вхід є:
# i1 — контраст поверхонь (≥2 класи `клас_поверхні`, нижче), i2 — рішення силуету (крій з обʼємом,
# той самий перелік `верхнє_пропорція.ОБʼЄМНІ_КРОЇ`). i4 (деталь ремесла) входу не має.
# ПОЗА ТРАУРОМ — ТЕЖ (рядок 1850): меню XII.3 загальне (мінімуми за наміром рахуються над
# {i1…i7}), а XIV.1 крок 9 велить тихі джерела в будь-якому стриманому контексті. Доти B1
# поза трауром рахував лише хрому, принт, гучну фактуру й мотив і стояв на 1 310 з 8 451
# нетраурних образів рук 1–2 збережених прогонів, з них 1 238 — з i1/i2 в образі
# (`проби/тихі_1850.py`).
# I1 — КОНТРАСТ КЛАСІВ ПОВЕРХНІ, НЕ БУДЬ-ЯКИХ ДВОХ КОДІВ (рядок 2450). Доти i1 давали будь-які дві
# різні `поверхня_речі`, і найчастіше це було шкіряне взуття чи сумка + поліестеровий верх: i1
# стояв на 8 167 з 8 451 нетраурних образів рук 1–2, і B1 провалювався лише на 72 — підлога
# інтересу, «main defence against convergence on the generic-safe uniform» (тема-4 XII.2), знову
# була мертва. Тема-4 XII.3 i1 — texture contrast, K-COMP-06 — «variety inside unity»: різниця
# ПОВЕРХНІ, яку видно, а не різниця складу (поліестер, бавовна, віскоза, еластан — одна гладка
# матова тканина). Тож коди зводяться до класів поверхні, і i1 — ≥2 різні класи. Гладка шкіра
# взуття, сумки й пояса — їхній типовий матеріал (1 536 з 2 160 пар взуття, 462 з 656 сумок), не
# рішення про фактуру: до контрасту вона не йде; замша, лак, велюр — ідуть. Невідомий код — сам
# собі клас (як доти), тож новий код волокна не гасить i1 мовчки; покриття — `проби/i1_2450.py`.
КЛАС_ПОВЕРХНІ = {
    **dict.fromkeys(("поліестер", "бавовна", "еластан", "поліамід", "віскоза", "трикотаж", "льон",
                     "нейлон", "акрил", "тенсел", "батист", "стрейч", "модал", "муслін", "ліоцел",
                     "knit-fine", "smooth-matte"), "гладка_матова"),
    **dict.fromkeys(("satin", "silk-shine", "smooth-shine", "patent"), "блиск"),
    **dict.fromkeys(("вʼязане", "вовна", "кашемір", "мохер", "альпака", "ангора", "knit-chunky",
                     "tweed-boucle"), "обʼємна"),
    **dict.fromkeys(("замша", "нубук", "велюр", "оксамит", "вельвет"), "ворс"),
    **dict.fromkeys(("мереживо", "гіпюр", "ажур", "шифон"), "ажур"),
    "leather": "шкіра", "denim": "денім"}
ШКІРА_ЯК_ОСНОВА = ("взуття", "сумка", "пояс")


def клас_поверхні(e):
    """Клас поверхні речі для i1 (`КЛАС_ПОВЕРХНІ`); замша й нубук — ворс, хоч фід дає їм
    `текстура` leather; None — поверхня невідома."""
    if e.get("волокно") in ("замша", "нубук"):
        return "ворс"
    п = поверхня_речі(e)
    return КЛАС_ПОВЕРХНІ.get(п, п) if п else None


def тихі_джерела(E):
    """i1 і i2 теми-4 XII.3 над речами з площею ≥3 %: перелік джерел як у `джерела_інтересу`."""
    from верхнє_пропорція import ОБʼЄМНІ_КРОЇ
    Р = [e for e in одна_на_річ(E) if (e.get("площа") or 0) >= 0.03]
    пов = {}
    for e in Р:
        к = клас_поверхні(e)
        if к and not (к == "шкіра" and e.get("слот") in ШКІРА_ЯК_ОСНОВА):
            пов.setdefault(к, e.get("річ") or e.get("id"))
    дж = []
    if len(пов) >= 2:
        дж.append(dict(річ=list(пов.values()), слот=None, важелі=["i1:" + "+".join(sorted(пов))]))
    дж += [dict(річ=e.get("річ") or e.get("id"), слот=e.get("слот"), важелі=["i2:" + e["крій"]])
           for e in Р if e.get("крій") in ОБʼЄМНІ_КРОЇ]
    return дж


def річ_несе_інтерес(r):
    """Чи ця ОДНА річ сама по собі — джерело інтересу (statement-річ): перелік важелів.

    Н-2 (28.09.2026). `джерела_інтересу` рахує інтерес над ЕЛЕМЕНТАМИ образу, і в
    них є площа — гейт «≥ 3 %» там на місці. Тут питання інше й площі не потребує:
    «чи ця сукня сама себе несе», і питає його структура образу, де елементів ще
    нема. Критерій — той самий `_важелі_інтересу`, другої копії порога немає.
    `lab` рахується з `hex`, коли його нема; нейтраль — та сама `колір_образу.нейтраль`."""
    if not isinstance(r, dict):
        return []
    e = dict(r)
    if not e.get("lab") and e.get("hex"):
        import colorspace as _КС
        try:
            e["lab"] = _КС.hx(e["hex"])
        except (TypeError, ValueError, AttributeError):
            e["lab"] = None
    if e.get("lab") and "нейтраль" not in e:
        import колір_образу as _КО
        e["нейтраль"] = _КО.нейтраль(tuple(e["lab"]))
    return _важелі_інтересу(e)

def _метрики_образу(E, темп_c=None, опади=None, вітер=None, речі=None,
                    стан=None, **kw):
    """⚠ `стан` — ІМЕНОВАНИЙ параметр, а не ключ у `**kw`, і це не стиль.
    07.09.2026 його додали через `**kw`, і він протік крізь цю функцію у
    `формальність_образу`, яка `**kw` не приймає: TypeError валив увесь
    `перевірити_образ`, а гейт досяжності впав із 44 % до 17 %. Рівно той клас,
    що й ручні білі списки: ключ їде далі, ніж його вміють прийняти. Іменований
    параметр робить межу видимою в сигнатурі."""
    """Скалярні метрики, за якими міряється «стало гірше». Тільки ті, що вже
    рахуються — нових метрик крок редагування не вигадує.

    ТЕПЛО ВХОДИТЬ У МЕТРИКИ (28.08.2026). Доти крок бачив лише когерентність нейтралей
    і формальність, тож при 6 °C «пальто можна зняти — жодна метрика не падає» було
    правдою за побудовою: тепла серед метрик не було. `погода()` уже рахує шари проти
    температури (K-WEA-01) і мовчить без темп_c, тому вона й береться — без вигадок."""
    зн = (нейтралі_крос(E) or []) + (формальність_образу(E, **kw) or [])
    if темп_c is not None or опади is not None:
        # шари рахуються З РЕЧЕЙ (погода(): «тепло — не питання видимості»); без
        # `речі` лічба падала на видимі елементи, і в стані «надворі» верх під
        # застібнутим пальтом не рахувався — «шарів замало» і з пальтом, і без,
        # тож пальто виходило «можна зняти» при +6 °C (спіймано гейтом §37 28.08)
        # СТАН ПЕРЕДАЄТЬСЯ (07.09.2026): без нього BREAKS правила K-MAT-03
        # («climate-controlled interiors») тут не діяв, і крок редагування рахував
        # сезонну семантику тканини навіть тоді, коли решта системи її утримує.
        # Дві половини одного правила давали різну відповідь у двох місцях.
        зн += (погода(E, темп_c=темп_c, опади=опади, вітер=вітер, речі=речі,
                      стан=стан) or [])
    return dict(
        знахідок=len(зн),
        вага_знахідок=round(sum(z.get("сила_нп") or 0.0 for z in зн), 3),
        # ІНТЕРЕС — ТІЄЮ САМОЮ ЛІНІЙКОЮ, ЩО Й ПІДЛОГА (рядок 2240). Доти тут стояли лише гучні
        # `джерела_інтересу`, а `підлога_інтересу_проактивно` рахує й тихі i1/i2: на сукні +
        # вовняному шарфі + взутті (усе нейтральне) база була 0, тож K-CRA-04 радив зняти шарф —
        # єдине джерело, після чого підлога не набрана. Виміряно `проби/тихі_ред_2240.py` на
        # 8 763 образах рук 1–2: K-CRA-04 знімав єдине джерело в 171 (53 з 312 траурних).
        інтерес=len(джерела_інтересу(E) + тихі_джерела(E)),
        слотів=len(одна_на_річ(E)))

# R-CHEV-11 — дубль `суд_образу.підлога_інтересу_проактивно`: «тьмяно й нічим не оживлено».
def підлога_інтересу_проактивно(E, intent="conventional", тихо=False):
    """K-INT-04 ПРОАКТИВНО (тема-4 XII.2 B1): скільки джерел інтересу образ МУСИТЬ нести
    за наміром — comfort/conventional/context ≥ 1, fashion_forward ≥ 2 (усі числа T3,
    фольклорні). Перенесено з composer._оцінити 24.08.2026: там підлога діяла лише під
    час ВИБОРУ, а ЗІБРАНИЙ образ із трьох нейтралей проходив review без жодного слова —
    гейт досяжності звітував гілку мертвою («три нейтралі — K-INT-04»).

    `тихо` — пул зібрано в траурному регістрі (рядок 154, мітка `траур_пулу` пакета):
    ремонт лише фактурою, без «АБО акцентний колір або принт» біля обличчя."""
    дж = джерела_інтересу(E) + тихі_джерела(E)   # i1/i2 — за будь-якого наміру (рядки 1680, 1850)
    # ПІДЛОГА — З ЛЕКСИКОНУ НАМІРУ (K-PER-00, 19.09.2026): доти «2» стояла тут
    # літералом під fashion_forward; comfort_first і context_optimal читають 1.
    мін = int(_намір(intent)["підлога"])
    # ТРАУР ПІДЛОГИ НЕ ЗНИЖУЄ (СХЕМА-КАРТКА, рядок 1481, звірено з корпусом 07.10.2026): мінімум —
    # за НАМІРОМ, без винятку нагоди (тема-4 XII.3: comfort/conventional/context ≥1); K-OCC-01
    # гасить на траурі яскраве й блиск біля обличчя, а не інтерес; тема-4 XIV.1 крок 9: «meet
    # the floor for the declared intent; in conservative contexts prefer quiet sources
    # (i1/i2/i4)». Тож `тихо` міняє РЕМОНТ (лише фактура), а не `мін`. Що підлога на похороні
    # стояла на 47–49 з 50 ідей — вада входу B1/B4, а не мінімуму: текстура відома лише на
    # шкірі взуття, сумки й пояса (рядок 1680, проба `підлога_траур_1481.py`); тихі джерела
    # i1/i2 вище — її ремонт.
    if len(дж) >= мін:
        return []
    # річ-вікно, чия хрома по обидва боки порога (рядок 3081): «нема інтересу» тут — не вирок
    _може = [e for e in одна_на_річ(E) if (e.get("площа") or 0) >= 0.03 and можливий_інтерес(e)]
    if len(дж) + len(_може) >= мін:
        import колір_річ as _КР
        return [_КР.без_входу_кольору(
            "K-INT-04", [(e,) for e in _може], перевірка="cannot_tell_item_carries_interest")]
    речі = [e.get("річ") or e.get("id") for e in одна_на_річ(E)]
    # ── K-COMP-06: У СТРИМАНОМУ КОНТЕКСТІ ФАКТУРА ЙДЕ ПЕРШОЮ ─────────────────
    # ЩО ТУТ СТОЯЛО І ЧОМУ ЦЕ БУЛО ГІРШЕ ЗА МОВЧАННЯ. Ремонт перелічував
    # «акцентний колір, принт або виразну фактуру» — саме в цьому порядку, —
    # і в дужках ЦИТУВАВ K-COMP-06 словами «у стриманому контексті спершу
    # фактура, не колір». Тобто те саме речення називало правило й робило
    # протилежне до того, що воно каже. У зведенні K-COMP-06 стояло «без сліду»,
    # і це було правдою навіть там, де його ім'я стояло в тексті.
    # ЩО КАЖЕ КОРПУС (тема-4, CHANGES, дослівно): «when the interest floor is
    # unmet in a conservative context, the system reaches for texture first, not
    # colour». Умова — стриманий намір; він тут уже порахований (`мін` вище
    # береться з того самого `_канон_намір`).
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ, І НЕ ЛИШЕ В ТЕКСТІ: разом із порядком міняється
    # ЗАПИТ У КАТАЛОГ. Доти він завжди просив хрому (`хрома_від`) — тобто шар
    # retrieval діставав вимогу кольору навіть там, де корпус просить фактури, і
    # правило не могло вплинути на добір пулу навіть у принципі. Тепер у
    # стриманому контексті запит іде по фактурі, і K-COMP-06 діє в першому з
    # трьох місць — у доборі, а не лише в реченні.
    # ── ТРАУРНИЙ ПУЛ: ФАКТУРА — ЄДИНИЙ РЕМОНТ (рядок 154) ───────────────────
    # Похорон — стриманий контекст за визначенням, хай який намір, тож фактура йде
    # першою й тут. Друге «АБО акцентний колір або принт біля обличчя» — рівно те,
    # чого K-OCC-01 на похороні не просить («no bright… no shine near the face»), і
    # пул рук 1–2 таких речей уже не має (`траурний_регістр.траурне_відсічення`):
    # порада кликала модель по річ, якої нема. ВИМІРЯНО (`проби/traur_154.py`: 3 траурні
    # сценарії × 10 образів): K-INT-04 — на 6 образах кожного, і всі 6 ремонтів із цим
    # «АБО»; на стенді (похорон, сіди 3/5/7) — рука 1 усіх трьох сідів.
    _стримано = тихо or _канон_намір(intent) not in ("fashion_forward", "statement", "editorial")
    _колір_ремонт = ("акцентний колір або принт у слоті, найближчому до обличчя")
    _фактура_ремонт = ("виразна фактура в слоті, найближчому до обличчя — у стриманому "
                       "контексті вона додає інтересу, не додаючи другого колірного "
                       "чи мотивного фокусу (K-COMP-06)")
    return [dict(_зн(
        "K-INT-04", "soft",
        "в образі %d джерел інтересу при підлозі %d" % (len(дж), мін),
        речі,
        "жодна річ не несе ні хроми ≥%.0f, ні принту, ні виразної фактури — образ "
        "складається лише з нейтралей. Підлога інтересу діє й на ЗІБРАНОМУ образі, не "
        "лише під час вибору" % ІНТЕРЕС_C_МІН,
        ремонт=(_фактура_ремонт if тихо          # один ремонт — рядком: «як варіант — …»
                else [_фактура_ремонт, "АБО " + _колір_ремонт] if _стримано
                else [_колір_ремонт, "АБО " + _фактура_ремонт]),
        запит=(dict(слот=None, фактура="виразна", чому="K-COMP-06: у стриманому "
                    "контексті інтерес підіймається фактурою, не другим кольором")
               if _стримано else
               dict(слот=None, хрома_від=ІНТЕРЕС_C_МІН,
                    чому="K-INT-04: підлога інтересу, проактивно")),
        ламається="підлога = %d і поріг хроми %.0f — КОНВЕНЦІЇ (T3). Мінімалістичний "
                  "образ із нейтралей може бути свідомим вибором — тому soft, не гейт. "
                  "І межа самого K-COMP-06, названа ним же: фактурний контраст на "
                  "фотографії й здалеку майже зникає (K-CRA-10), а наш рендер і Є "
                  "фотографія — тобто порада працює в житті сильніше, ніж у показі"
                  % (мін, ІНТЕРЕС_C_МІН),
        поріг=float(мін), вимір=float(len(дж)), повна=float(мін + 1),
        заяви=[_ВМ.заява("interest_sources_below_floor", count=len(дж), floor=мін)],
        ремонт_заяви=([_ВМ.заява("texture_near_face")] if тихо else [_ВМ.заява("texture_near_face"), _ВМ.заява("accent_colour_or_print_near_face")] if _стримано else [_ВМ.заява("accent_colour_or_print_near_face"), _ВМ.заява("texture_near_face")])),
        також_правила=(["K-COMP-06"] if _стримано else None),
        сила_нп_джерело="вимір (власний: брак джерел до підлоги)")]
def крок_редагування(E, темп_c=None, опади=None, вітер=None, речі=None,
                     стан=None, intent="conventional", E_без_шару=None, **kw):
    """K-CRA-04 × K-INT-04. (зайві, заборонені_до_видалення, база).
    `темп_c/опади/вітер` — щоб видалення шару, який гріє, рахувалось погіршенням;
    `речі` — щоб шари рахувались із речей (светр під застібнутим пальтом гріє).
    `intent` — намір жінки: підлога інтересу — з лексикону наміру, як у
    `підлога_інтересу_проактивно` (рядок 2590). `E_без_шару` — образ, який видно,
    коли верхній шар знято (стан «у_приміщенні»): кандидат «без пальта» в стані
    «надворі» — це він, а не E мінус пальто, бо пальто ховало сукню чи верх (рядок 2016).

    `зайві` — елементи, чиє видалення не погіршує ЖОДНОЇ метрики.
    `заборонені` — ті, чиє видалення прибрало б інтерес нижче підлоги: для них
    ремонт — ЗАМІНА на тихіше джерело, не видалення."""
    # ── БАЗА Й КАНДИДАТ МІРЯЮТЬСЯ ОДНІЄЮ ЛІНІЙКОЮ (08.09.2026) ───────────────
    # ЩО ТУТ СТОЯЛО: база рахувалась БЕЗ `стан`. `стан` — іменований параметр цієї
    # функції, тож у `**kw` він фізично не потрапляє, а кандидат нижче дістає його
    # явно (`стан=стан`). Наслідок: база завжди мірялась «надворі»
    # (`погода`: `надворі = (стан != "у_приміщенні")` → True при None), а кандидат —
    # у стані виклику. `pipeline` кличе саме з `стан="у_приміщенні"`.
    #
    # Виміряно 08.09.2026 на образі «верх + низ + замшеві черевики + шарф», −10 °C, дощ:
    #     стан=None            → знахідок 2, вага 2.00     ← так мірялась БАЗА
    #     стан="у_приміщенні"  → знахідок 1, вага 1.00     ← так мірявся КАНДИДАТ
    # Тест «гірше» через це систематично зсунутий у бік «зняти можна», і на цьому
    # самому вході K-CRA-04 радив: «шарф можна зняти — жодна метрика не падає».
    # Що справді стається без шарфа при −10 °C: K-WEA-01 «шарів замало» силою 1.0
    # і «нижче −8 °C палітру несуть шапка-шарф-рукавиці» силою 0.6. Тобто це була
    # порада людині зняти шарф у мороз.
    #
    # Пояснення знахідки себе й видавало: «вага 1.60 (було 2.00)» — вага впала ВІД
    # ВИДАЛЕННЯ речі, що при симетричному вимірі неможливе.
    база = _метрики_образу(E, темп_c=темп_c, опади=опади, вітер=вітер, речі=речі,
                           стан=стан, **kw)
    # ПІДЛОГА — ЗА НАМІРОМ, ТІЄЮ САМОЮ ЛІНІЙКОЮ, ЩО Й B1 (рядок 2590). Доти тут стояла стала
    # ПІДЛОГА_ІНТЕРЕСУ = 1, а `підлога_інтересу_проактивно` читає мінімум з лексикону наміру
    # (fashion_forward ≥ 2): за сміливого наміру K-CRA-04 радив зняти друге джерело, і той самий
    # образ одразу падав на K-INT-04. Тепер `мін` — `_намір(intent)["підлога"]` (conventional,
    # comfort, context — 1, тобто як доти), і заборона — коли видалення ЗНИЖУЄ інтерес, а
    # образ без речі під підлогою. Друга умова доти була «база ≥ підлоги»: за підлоги 1 це те
    # саме, а за 2 образ з одним джерелом інакше дістав би пораду зняти саме його.
    мін = max(ПІДЛОГА_ІНТЕРЕСУ, int(_намір(intent)["підлога"]))
    шарів = sum(1 for x in одна_на_річ(E) if x.get("слот") == "верхній_шар")
    зайві, заборонені = [], []
    for e in одна_на_річ(E):
        if e.get("слот") not in ЗНІМНІ_СЛОТИ: continue
        без = [x for x in E if (x.get("річ") or x.get("id")) != (e.get("річ") or e.get("id"))]
        # КАНДИДАТ «БЕЗ ПАЛЬТА» ВІДКРИВАЄ ТЕ, ЩО ПАЛЬТО ХОВАЛО (рядок 2016). У стані «надворі»
        # застібнутий шар ховає сукню чи верх (`outfit.елементи`), і E мінус пальто — образ без
        # сукні: нейтралі, інтерес і K-KOH-05 «мусить бути сукня» міряли річ, якої нема.
        if e.get("слот") == "верхній_шар" and шарів == 1 and E_без_шару is not None:
            без = list(E_без_шару)
        _ключ_e = (e.get("річ") or e.get("id"))
        без_речей = [р for р in (речі or []) if (р.get("назва") or р.get("id")) != _ключ_e and р.get("id") != _ключ_e] if речі else None
        м = _метрики_образу(без, темп_c=темп_c, опади=опади, вітер=вітер, речі=без_речей,
                            стан=стан, **kw)
        гірше = (м["знахідок"] > база["знахідок"]
                 or м["вага_знахідок"] > база["вага_знахідок"] + 1e-9)
        if гірше: continue
        # «оголить» — лише коли видалення ЗНИЖУЄ інтерес і лишає образ під підлогою. Річ,
        # без якої інтерес не падає, нічого не тримає: про порожнечу вже каже
        # підлога_інтересу_проактивно. Спіймано 28.08.2026 (холодна-темна · прогулянка):
        # «сумка тримає образ» і «в образі 0 джерел інтересу» стояли в ОДНІЙ знахідковій
