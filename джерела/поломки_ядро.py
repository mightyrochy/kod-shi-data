# Правила переліку, яких рука 2 не ламає: вхід рахується, жереб їх не бере.
ПОЗА_ЖЕРЕБОМ = frozenset({"R-MUA-02"})


# ── ПРОГІН: ЩО ЗЛАМАНО Й ЗА ЧИМ СТЕЖАТЬ У ЦЬОМУ ВИКЛИКУ МОСТУ ───────────────────
# Стан один, і ставлять його лише входи мосту: пакет каталогу (`міст_пакет.пакет_каталогу`, пакет руки 2
# в `міст_рука2._рука2`), суд (`міст_відповіді.від_моделі` під `у_сесії`), брифи рук (`міст_запити._брифи`) і фігура
# опису (`міст_опис`). Поза ними прогін порожній:
# `злам` віддає справне значення, тож рука 1, руки 3–4, CLI й гейти правил поломок не бачать. Правило про
# руку не питає — воно віддає своє значення точці зламу. Стежене правило (рука 1 того самого прогону) діє
# й пише свою дію в тінь (`свідок`, `відсіяти`): так звіт пари знає, чи правило діяло і в неї.
# Параметр, а не контекст, протягти неможливо без зміни сигнатур десятків функцій рук 1, 3, 4: місця дії
# лежать на глибині 5–8 викликів від мосту.
Прогін = _кол.namedtuple("_Прогін", "зламані стежені тінь")
ПРОГІН = _cv.ContextVar("поломки_прогін", default=Прогін(frozenset(), frozenset(), None))
# Скільки разів код ПИТАВ, за чим стежать (`стежені`). Кеш за входом (`кеш_входу`) читає цей лічильник до й
# після побудови: побудова, що не питала, від стежених не залежить, і її вихід віддається за будь-якого
# набору стежених; та, що питала, лишається під ключем із ним.
ПИТАЛИ_СТЕЖЕНІ = [0]
# Усі коди, які рука 2 може зламати: коди правил переліку, крім тих, що поза жеребом.
ЗЛАМНІ = frozenset(к for з in ПЕРЕЛІК if з["ід"] not in ПОЗА_ЖЕРЕБОМ for к in з["коди"])


@_cl.contextmanager
def прогін(зламані=(), стежити=()):
    """Усе всередині — прогін, у якому правила `зламані` хиблять за реєстром, а `стежити` діють і пишуть
    свою дію в тінь. Тінь — заново; вкладений прогін і виняток відновлюють попередній."""
    т = ПРОГІН.set(Прогін(frozenset(зламані or ()) & ЗЛАМНІ, frozenset(стежити or ()), []))
    try:
        yield
    finally:
        ПРОГІН.reset(т)


def у_сесії(ф):
    """Декоратор ендпойнта: усередині — свіжий порожній прогін, на виході — попередній.

    Так `увімкнути`/`стежити_за` (суд дізнається правила лише після жеребу, глибоко в тілі ендпойнта) не
    протікають ні в наступний виклик, ні в іншу руку. `functools.wraps` лишає джерело самого ендпойнта."""
    @_ft.wraps(ф)
    def обгортка(*a, **kw):
        with прогін():
            return ф(*a, **kw)
    return обгортка


def увімкнути(коди):
    """Застосувати жереб до кінця `у_сесії`: правила `коди` хиблять; тінь — заново."""
    п = ПРОГІН.get()
    ПРОГІН.set(п._replace(зламані=frozenset(коди or ()) & ЗЛАМНІ, тінь=[]))


@_cl.contextmanager
def зламано(коди):
    """Усе всередині хибить правилами `коди` (порожньо — справне); стежені й тінь прогону ті самі. Бриф і фігура
    опису: в одному виклику мосту стоять бриф руки 1 і бриф руки 2, а що зламано, каже один стан."""
    т = ПРОГІН.set(ПРОГІН.get()._replace(зламані=frozenset(коди or ()) & ЗЛАМНІ))
    try:
        yield
    finally:
        ПРОГІН.reset(т)


def стежити_за(коди):
    """Стежити за `коди` до кінця `у_сесії` (суд руки 1 після жеребу): правило діє, дія — у тінь."""
    п = ПРОГІН.get()
    ПРОГІН.set(п._replace(стежені=frozenset(коди or ()), тінь=[]))


def зламані():
    """Коди правил, що хиблять у цьому прогоні (порожньо поза рукою 2)."""
    return ПРОГІН.get().зламані


def стежені():
    """Коди, за якими стежать у цьому прогоні (порожньо поза рукою 1 прогону); читання лічиться."""
    ПИТАЛИ_СТЕЖЕНІ[0] += 1
    return ПРОГІН.get().стежені


def стан_стежених():
    """Те саме, що `стежені()`, без лічби: для ключа кешу, а не для рішення правила."""
    return ПРОГІН.get().стежені


def у(код, наб):
    """Код у наборі. Суфіксний варіант (`K-CRA-01-N`) — разом із базою, коли в наборі база;
    варіант у наборі (`K-COL-06-M`) базу (`K-COL-06`) НЕ тягне."""
    if not наб or not код:
        return False
    к = str(код)
    return к in наб or (ІП.суфікс(к) is not None and ІП.база(к) in наб)


def свідок(код, де, **поля):
    """Місце дії правила: коли за правилом стежать, його дія лягає в тінь (звіт: чи правило діяло)."""
    if у(код, стежені()):
        в_тінь(код, де, **поля)


# (код, точка) → функція(справне значення, **дані місця дії): заповнює `поломки` своїм імпортом (рядок над
# цим модулем, К-4); правило зламане лише в прогоні, який ставлять входи мосту, що імпортують `поломки`.
ТОЧКИ = {}


def злам(код, точка, справне, **дані):
    """Точка зламу правила `код`: справне значення — те, що порахувало правило; повертає значення прогону.

    Поза рукою 2 (і коли правило не зламане) — те саме значення. Зламане — функція `ТОЧКИ[(код, точка)]`
    з тим самим значенням і `дані` місця дії; вона ж кладе в тінь обидві рекомендації."""
    if not у(код, ПРОГІН.get().зламані):
        return справне
    return ТОЧКИ[(код, точка)](справне, **дані)


def позначити(z):
    """Справну знахідку зламаного правила (`_придушити`) — у тінь на місці народження: не блокує, не
    важить, не ремонтує й не просить каталог, навіть там, де її ніхто не відсіє. Повторно — теж: емітенти
    пишуть `dict(_зн(...), сила_нп=X)`, копія несе позначену тінь, але повернуту вагу, і `обмежити_вагу`
    перед сумою ранжу кличе цю функцію знову. Повертає ту саму знахідку."""
    if isinstance(z, dict) and z.get("придушено_руки_2"):
        if not z.get("тінь_руки_2"):
            z["тінь_руки_2"] = dict(блокувала=bool(z.get("блокує")), сила=z.get("сила"),
                                   сила_нп=z.get("сила_нп"))
        z["блокує"] = False
        z["сила_нп"], z["сила_нп_джерело"] = 0.0, "rule_off_hand_2"
        for к in ("ремонт", "запит_у_каталог", "ремонт_заяви"):
            z.pop(к, None)
    return z


def відсіяти(знахідки, образ=None):
    """Точка збору суду: справні знахідки зламаного правила — геть у тінь, хибні лишаються й лягають у тінь
    з обома рекомендаціями; знахідка стеженого правила лишається й лише записується. `образ` — id речей
    образу, що судиться: тінь несе його, і картка бере лише свої знахідки (`тінь_образу`)."""
    стеж, злам_ = стежені(), ПРОГІН.get().зламані
    if not (стеж or злам_):
        return знахідки
    лишити = []
    for z in знахідки or []:
        п = z.get("правило") if isinstance(z, dict) else None
        # посадка, силует і вартість носіння судять речі, а не весь образ: рекомендації таких емітентів
        # їдуть на самій знахідці (`хибна_руки_2`), а в тінь з повним складом їх кладе ця точка
        хр = z.get("хибна_руки_2") if у(п, злам_) else None
        придушено = bool(хр and z.get("придушено_руки_2"))
        if у(п, стеж) or хр:
            т = z.get("тінь_руки_2") or {}
            в_тінь(п, "judge", сила=т.get("сила", z.get("сила")),
                   блокувала=т.get("блокувала", bool(z.get("блокує"))),
                   образ=sorted(map(str, образ or [])), речі=[str(х) for х in z.get("речі") or []],
                   суть=z.get("суть"), **(dict(хр, сила_нп=т.get("сила_нп", z.get("сила_нп"))) if хр else {}))
        if not придушено:
            лишити.append(z)
    return лишити


def в_тінь(правило, де, **поля):
    """Записати в тінь дію правила (фільтр пулу, рядок промпту, знахідка), щоб `правило_діяло` бачило
    всі місця дії."""
    тінь_ = ПРОГІН.get().тінь
    if тінь_ is not None:
        тінь_.append(dict(правило=правило, де=де, **поля))


def тінь():
    """Що правила зробили в цьому прогоні (копія переліку)."""
    return list(ПРОГІН.get().тінь or [])
