"""Вікна аксесуарів, що зберігають вибір у маленькому слоті."""

from slots import СЛОТИ_БЕЗ_ВІКНА_КОЛЬОРУ as СЛОТИ_БЕЗ_ВІКНА

def розкрити_аксесуари(спец):
    """Вікна аксесуарних слотів розтягуються на всю шкалу.

    ЧОМУ РОЗТЯГУЄМО, А НЕ ЗНІМАЄМО. Зняти вікно означало б вести аксесуари іншим
    шляхом, ніж решту, — два кодові шляхи, які розійдуться на першій же правці
    палітри. Тут той самий рушій із тими самими полями, просто межі ширші.

    ЩО ЦЕ МІНЯЄ НАД РЕАЛЬНОЮ РІЧЧЮ (зміряно на каталог_повний, профіль
    #f2d6c4/#4a4644): сережок крізь вікно проходило 7 зі 134 у каталозі, намист
    5 з 56, кольє 7 з 38, каблучок 12 з 27. Підлога вибірки в 20 речей на таких
    числах недосяжна в принципі. Після розтягу слот віддає те, що каталог має.

    МЕЖА. Верх, сукня й верхній шар НЕ чіпаються: там колір лежить біля обличчя,
    і K-CLR-02 («контраст біля обличчя нижчий за власний») — головне правило
    системи. Послабити його заради кількості означало б проміняти рушій на пул.
    """
    out = []
    for q in спец:
        if isinstance(q, dict) and q.get("слот") in СЛОТИ_БЕЗ_ВІКНА:
            q = dict(q, L_min=0, L_max=100, C_min=0.0, C_max=140.0)
        out.append(q)
    return out
