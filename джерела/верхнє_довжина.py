ПОРІГ_ЗРОСТУ_K_OUT_02 = 167.6
НИЖЧЕ_КОЛІНА = ("литка", "щиколотка", "максі")
# Голос пулу. Ранг пулу — тайбрейк серед рівних, і він бінарний: дробова сила
# не може впорядкувати рівні речі тонше, ніж «довге після короткого». Тому сила тут не градує
# ранг, а вирішує, ЧИ він діє: лише поки пропорція тримає більшість свого голосу проти тепла
# (K-OUT-01). Частка придушення — 1.0 у морозній смузі погоди й 0.0 поза нею (`суд_погода.придушення`:
# усередині смуги рампи нема); від половини тепло має більшість, і довге пальто на невисокій
# лишається в ряду рівних — у зріз пулу воно не програє короткому.
# Половина — [конвенція]: межа більшості, не число джерела (джерела кажуть словами).
ПРИДУШЕННЯ_ПУЛУ = 0.5


def нижче_коліна(р, H=None):
    """(так/ні/None, код джерела): чи поділ верхнього шару нижче коліна.

    Відповідь дає лише слово крамниці чи фото (`довжина_рівень` у `НИЖЧЕ_КОЛІНА`): класифікація
    речі, не порівняння двох боків. Вимір довжини виробу (Ф-9) бока не називає: поділ на її тілі —
    рівень точки виміру мінус довжина, коліно — інший рівень, і обидва — частки зросту
    (`areas.РІВНІ`, T3), похибки яких ні повтор, ні визнане джерело не дають (рішення менеджера
    06.11, п.3; `ДОПУСК_ДОВЖИНИ_ВИРОБУ_СМ`). Тож річ із виміром і без слова — None
    (`measured_length_knee_unknown`); слово, яке composer вивів із того самого виміру
    (`довжина_джерело` «вимір: …»), словом крамниці не є. `H` лишено для підпису читачів."""
    слово = р.get("довжина_рівень")
    if слово and not str(р.get("довжина_джерело") or "").startswith("вимір"):
        return слово in НИЖЧЕ_КОЛІНА, "length_word"
    if довжина_виробу(р)[0] is not None:
        # ТОЧКА ПІДКЛЮЧЕННЯ похибки рівня тіла (та сама, що в `розрив_країв`): із записом — поділ на її тілі
        # (рівень точки − довжина) проти коліна, бік лише понад похибку обох; доки запису нема — «невідомо».
        return None, "measured_length_knee_unknown"
    return None, "length_unknown"


def сила_зросту(зріст):
    """K-OUT-02: неперервна сила недобору зросту до смуги джерела (0 — від 167.6 см угору)."""
    if not зріст:
        return 0.0
    відхил = (ПОРІГ_ЗРОСТУ_K_OUT_02 - float(зріст)) / ПОРІГ_ЗРОСТУ_K_OUT_02
    return round(max(0.0, min(1.0, відхил * 6.0)), 2)


def ранг_пулу(тіло, смуга_погоди):
    """K-OUT-02 у ПУЛІ: сила, з якою довгий
    верхній шар іде ПІСЛЯ рівних у доборі слота, або 0.0. Та сама сила, що в суді, і так само
    підпорядкована K-OUT-01: у морозній смузі погоди (frost, deep_frost) теплова функція
    забирає голос пропорції (`суд_погода.придушення` бере СМУГУ, не градуси), тож довге
    пальто на невисокій лишається в ряду рівних — корпус каже «потрібне тепло — бери довше»
    (Lamport). Смуги нема — придушення нема (те саме «не вгадуємо», що й у суді). Від частки
    `ПРИДУШЕННЯ_ПУЛУ` — 0.0: тепло має більшість голосу, і бінарний ранг пулу не діє; суд
    свою ослаблену знахідку лишає."""
    с = сила_зросту((тіло or {}).get("зріст"))
    if not с:
        return 0.0
    пр = _ВП.придушення(смуга_погоди)
    ч = пр["частка"] if пр else 0.0
    if ч >= ПРИДУШЕННЯ_ПУЛУ:
        return 0.0
    return round(с * (1.0 - ч), 2)


