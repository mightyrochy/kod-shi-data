# ── ПОРЯДОК ШАРІВ У КАСКАДІ — УМОВА, А НЕ МОВЧАЗНЕ ПРИПУЩЕННЯ (Н-outer-1-074) ─
# `краї_.sort()` робить послідовність монотонною ЗАВЖДИ, тож «монотонно зростаючі
# краї» ніколи нічого не відсіювали: перевіряється КРОК і — тепер — ПОРЯДОК ШАРІВ.
# Каскад читається як рішення тільки коли зовнішній шар НАЙДОВШИЙ: пальто, з-під
# якого визирає кардиган, з-під якого блуза. Перевернутий порядок (пальто коротше
# за те, що під ним) — це рівно та поломка, яку K-OUT-03 карає штрафом, а старий
# `_каскад` зараховував її як «оголошений каскад» і штраф СКАСОВУВАВ.
# Константа іменована навмисно: якщо власник вирішить, що три внутрішні шари теж
# утворюють каскад, це буде видима зміна одного значення, а не мовчазна умова.
КАСКАД_ЗОВНІШНІЙ_НАЙДОВШИЙ = True
КАСКАД_СЛОТИ = ("верх", "верхній_шар", "сукня")


КАСКАД_НЕВІДОМО = "невідомо"


def каскад_шарів(речі, тіло=None):
    """K-OUT-04: dict (каскад), None (каскаду нема) чи `КАСКАД_НЕВІДОМО`.

    Каскад — три і більше шари (`КАСКАД_СЛОТИ`), ЗОВНІШНІЙ ШАР НАЙДОВШИЙ, кожен крок між
    сусідніми краями в смузі 2–5 см. Два шари каскаду не утворюють — нема напрямку, який можна
    прочитати. Порядок і кроки — лише з довжин від однієї точки тіла (як `розрив_країв`), з похибкою
    обох шарів пари: шар без такого виміру — каскад невідомий (доти край зі слова чи рівня тіла
    давав кроки шаблону тіла). Крок у смузі — коли в ній уся вилка «крок ± похибка»; поза — коли
    вся вилка поза нею; порядок — коли зовнішній шар довший за кожен інший понад похибку пари.
    Що з цього в межах похибки — невідомо. `тіло` лишено для підпису читачів."""
    шари = [р for р in речі if р.get("слот") in КАСКАД_СЛОТИ]
    if len(шари) < 3:
        return None
    зовн = next((р for р in шари if р.get("слот") == "верхній_шар"), None)
    if КАСКАД_ЗОВНІШНІЙ_НАЙДОВШИЙ and зовн is None:
        return None
    виміри = [довжина_виробу(р) for р in шари]
    if any(д is None for д, _т, _п in виміри) or len({т for _д, т, _п in виміри}) > 1:
        return КАСКАД_НЕВІДОМО
    порядок_відомий = True
    if КАСКАД_ЗОВНІШНІЙ_НАЙДОВШИЙ:
        дз, _тз, пз = довжина_виробу(зовн)
        різниці = [(дз - д, пз + п) for (д, _т, п), р in zip(виміри, шари) if р is not зовн]
        if any(різн < -пох for різн, пох in різниці):
            return None                    # інший шар довший за зовнішній понад похибку
        порядок_відомий = all(різн > пох for різн, пох in різниці)
    ряд = sorted(zip(виміри, шари), key=lambda x: (-x[0][0], x[1] is not зовн))
    кроки = [(round(ряд[i][0][0] - ряд[i + 1][0][0], 1), round(ряд[i][0][2] + ряд[i + 1][0][2], 2))
             for i in range(len(ряд) - 1)]
    низ, верх = C["каскад_крок_низ_см"], C["каскад_крок_верх_см"]
    if any(к - пох > верх or к + пох < низ for к, пох in кроки):
        return None
    if порядок_відомий and all(низ <= к - пох and к + пох <= верх for к, пох in кроки):
        return dict(речі=[_імʼя(р) for _, р in ряд], кроки=[к for к, _ in кроки], ід=[р.get("id") for _, р in ряд])
    return КАСКАД_НЕВІДОМО
