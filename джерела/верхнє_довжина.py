# Тож край, поставлений рівнем тіла (слово → рівень → висота, геометрія «річ», дефолт слота),
# похибки не має, і бік з ним — «невідомо». Відомий лише розрив двох виробів, виміряних від
# ОДНІЄЇ точки тіла: рівень точки тоді скорочується, лишається різниця двох довжин.
ДОПУСК_ДОВЖИНИ_ВИРОБУ_СМ = 1.27


def довжина_виробу(р):
    """(довжина см, точка виміру, похибка см) або три None — вимір крамниці, без тіла.

    Зібрана річ, чий поділ composer з довжини не взяв (`край_джерело` не «виріб»: число поза тілом
    чи власна геометрія речі), виміру не несе: її довжина — «число не з цієї речі»."""
    дов, точка = р.get("довжина_виробу_см"), р.get("довжина_виробу_точка")
    if дов is None or not точка or р.get("край_джерело") not in (None, "виріб"):
        return None, None, None
    return float(дов), точка, round(ДОПУСК_ДОВЖИНИ_ВИРОБУ_СМ + float(р.get("довжина_виробу_розкид_см") or 0.0), 2)


def розрив_країв(в, н):
    """(Δ см, похибка см, код): край речі `в` мінус край речі `н` на тому самому тілі, зі знаком
    `край_см` (Δ > 0 — край `в` вище, тобто `в` КОРОТША), або (None, None, код).

    Відомий лише між двома виробами з довжиною від однієї точки тіла: Δ = довжина `н` − довжина `в`,
    похибка — сума похибок обох довжин. Інакше бік і різницю код не називає: `edge_not_measured`
    (край — слово, геометрія чи дефолт: рівень тіла без похибки), `measured_from_different_points`
    (пальто від плеча, спідниця від талії: між точками — рівні тіла без похибки)."""
    дв, тв, пв = довжина_виробу(в)
    дн, тн, пн = довжина_виробу(н)
    if дв is None or дн is None:
        return None, None, "edge_not_measured"
    if тв != тн:
        # ТОЧКА ПІДКЛЮЧЕННЯ похибки рівня тіла як частки зросту: її пише одним записом окрема частина
        # (`джерела/похибка_вимірів_тіла.py`, ANSUR II — рішення менеджера 06.11 «джерела похибки вимірів
        # тіла», п.3–4). Із записом тут — краї обох речей на її тілі (рівень точки − довжина) і похибка:
        # допуск сітки плюс похибка рівня точки кожної; доки запису нема — «невідомо».
        return None, None, "measured_from_different_points"
    return round(дн - дв, 1), round(пв + пн, 2), "measured_same_point"


def факти_краю(р):
    """Що код знає про край речі без тіла — для заяви моделі: слово рівня, довжина й точка виміру."""
    дов, точка, пох = довжина_виробу(р)
    return dict(level=р.get("довжина_рівень"), length_cm=дов, point=точка, error_cm=пох)


def край_см(р, тіло):
    """Край речі в сантиметрах ВІД ПІДЛОГИ на профілі КОНКРЕТНОГО тіла.

    Джерело краю повертається разом зі значенням, і це не косметика: вимір над
    дефолтом слота — рівно той антипатерн, який корпус уже ловив («вимір над
    заглушкою»). Правило, що дістало край із дефолту, мусить вийти ПИТАННЯМ.

    ЧОТИРИ ДЖЕРЕЛА, НЕ ТРИ (Н-outer-1-073): composer віддає край зі СЛОВА назви
    вже переведеним у сантиметри на цьому тілі (`край_джерело="слово"`,
    composer.py:1256). Це не дефолт слота: число походить із входу, лише
    м'якшого тіру, ніж вимір речі. Без цієї гілки правило називало його
    заглушкою і просило довжину, яка вже прийшла. Тіла тут може не бути
    (канал 3 кличе з `тіло=None`) — тому гілка окрема, а не залежна від висот.
    """
    рівень = р.get("довжина_рівень")
    if рівень and тіло:
        h = _КР.висота_рівня(рівень, тіло.get("висоти") or {})[0]
        if h is not None:
            return float(h), ДЖ_РІВЕНЬ % рівень
    if р.get("низ_см") is not None and р.get("край_джерело") == "річ":
        return float(р["низ_см"]), ДЖ_РІЧ
    if р.get("низ_см") is not None and р.get("край_джерело") == "слово":
        return float(р["низ_см"]), ДЖ_СЛОВО
    if р.get("низ_см") is not None:
        return float(р["низ_см"]), ДЖ_ДЕФОЛТ
    return None, ДЖ_НЕМА


