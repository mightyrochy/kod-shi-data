# ── K-OUT-02: ОДНА СИЛА НА СУД І НА ПУЛ ─────────────────────────
# Драбина Lamport: нижче коліна й довше — найкраще приблизно від 167.6 см угору. Межу
# узято [конвенцією] (три українські джерела дають три різні числа), напрям — погоджений.
