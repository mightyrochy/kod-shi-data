ДЖ_РІЧ = "виміряна довжина речі"
ДЖ_РІВЕНЬ = "слово назви → рівень «%s» → висота на цьому тілі"
ДЖ_СЛОВО = "слово назви → рівень → висота (composer)"
ДЖ_ДЕФОЛТ = "дефолт слота"
ДЖ_НЕМА = "краю нема"
ДЖЕРЕЛА_КРАЮ = (ДЖ_РІЧ, ДЖ_РІВЕНЬ, ДЖ_СЛОВО, ДЖ_ДЕФОЛТ)


def край_см(р, тіло):
    """Край речі в сантиметрах ВІД ПІДЛОГИ на профілі КОНКРЕТНОГО тіла.

    Джерело краю повертається разом зі значенням, і це не косметика: вимір над
    дефолтом слота — рівно той антипатерн, який корпус уже ловив («вимір над
    заглушкою»). Правило, що дістало край із дефолту, мусить вийти ПИТАННЯМ.

    ЧОТИРИ ДЖЕРЕЛА, НЕ ТРИ (Н-outer-1-073): composer віддає край зі СЛОВА назви
    вже переведеним у сантиметри на цьому тілі (`край_джерело="слово"`,
    composer.py:1256). Це не дефолт слота: число походить із входу, лише
    м'якшого тіру, ніж вимір речі. Без цієї гілки правило називало його
    заглушкою і просило довжину, яка вже прийшла. Тіла тут може не бути
    (канал 3 кличе з `тіло=None`) — тому гілка окрема, а не залежна від висот.
    """
    рівень = р.get("довжина_рівень")
    if рівень and тіло:
        h = (тіло.get("висоти") or {}).get(_РІВЕНЬ_У_ВИСОТУ.get(рівень, рівень))
        if h is not None:
            return float(h), ДЖ_РІВЕНЬ % рівень
    if р.get("низ_см") is not None and р.get("край_джерело") == "річ":
        return float(р["низ_см"]), ДЖ_РІЧ
    if р.get("низ_см") is not None and р.get("край_джерело") == "слово":
        return float(р["низ_см"]), ДЖ_СЛОВО
    if р.get("низ_см") is not None:
        return float(р["низ_см"]), ДЖ_ДЕФОЛТ
    return None, ДЖ_НЕМА


# Смуги K-OUT-23 — ЄДИНІ сантиметри довжини в усій темі, і вони абсолютні.
# Urban City дає ЧАСТКУ зросту (стегно ≈25–30 %, коліно ≈45–55 %), і частка
# правильніша за побудовою: 55–60 см — це 37 % від 160 см і 33 % від 180, тобто
# «коротка» означає різне на різних людях, а джерело цього не помічає.
ДУБЛЯНКА_КОРОТКА_СМ = (55.0, 60.0)      # T3, фольклорна константа, LuisaViaRoma
ДУБЛЯНКА_ДОВГА_СМ = (95.0, 105.0)       # те саме джерело
ЧАСТКА_ЗРОСТУ = {"стегно": (0.25, 0.30), "коліно": (0.45, 0.55)}   # T3, Urban City


def довжина(речі, тіло=None):
    """K-OUT-02 (довжина масштабується зі зростом) і K-OUT-23 (єдині сантиметри
    теми — і вони сперечаються з часткою зросту)."""
    зн = []
    в = _верхній(речі)
    if в is None or not тіло:
        return зн
    рівень = в.get("довжина_рівень")
    зріст = тіло.get("зріст")
    if not рівень or not зріст:
        return зн
    низ, дж = край_см(в, тіло)
    плечі = (тіло.get("висоти") or {}).get("плечі")
    if низ is None or плечі is None:
        return зн
    довж = плечі - низ                      # довжина ВИРОБУ, не висота краю
    частка = довж / зріст
    # ── K-OUT-02: НЕПЕРЕРВНИЙ ЧЛЕН, НЕ ФІЛЬТР ───────────────────────────────
    # Драбина Lamport: коротке — для невисоких і мʼякого клімату; три чверті — для
    # більшості середніх; нижче коліна — від ~167.6 см. Напрям джерела погоджений,
    # МЕЖІ — ні: три українські джерела дають три різні числа на те саме питання.
    # Тому в код узято НАПРЯМ, а межа лишається [конвенція].
    поріг_зросту = 167.6
    if рівень in ("литка", "максі"):
        відхил = (поріг_зросту - зріст) / поріг_зросту
        сила_нп = round(max(0.0, min(1.0, відхил * 6.0)), 2)
        if сила_нп > 0:
            зн.append(dict(_зн("K-OUT-02", "default",
                "довга річ на зрості %.0f см: довжина входить у ранг, а не у фільтр"
                % зріст, [_імʼя(в)],
                "нижче коліна й довше найкраще працює приблизно від %.1f см угору, і "
                "краще ПРИТАЛЕНЕ, ніж підперезане (Lamport, AICI CIP). Тут зріст %.0f, "
                "тобто %.0f см недобору — це неперервний член ранжування верхніх шарів, "
                "а НЕ відсів: правило підпорядковане K-OUT-01 і в холоді мовчить"
                % (поріг_зросту, зріст, поріг_зросту - зріст),
                ремонт=["коротший верхній шар — або цей самий, приталений у талії "
                        "замість підперезаного"],
                ламається="ТРИ українські джерела дають ТРИ різні числові смуги на те "
                          "саме питання, і одне з них інвертує міркування. Напрям "
                          "ефекту погоджений, МЕЖІ — ні; смуги лишаються [конвенція]. "
                          "І число джерела — одне кругле в імперських одиницях (5\'6\")",
                поріг=поріг_зросту, вимір=float(зріст)),
                сила_нп=сила_нп,
                сила_нп_джерело="вимір: недобір зросту до смуги джерела, неперервно"))
            _СЛ.запис("K-OUT-02", "довжина проти зросту", "довжина",
                      значення="%.0f см, рівень %s" % (зріст, рівень), сила=сила_нп,
                      напрям="ранг, не фільтр")
    # ── K-OUT-23: абсолютні сантиметри проти частки зросту ───────────────────
    if (в.get("тип_верхнього") in ("дублянка", "шуба")
            or рівень in ЧАСТКА_ЗРОСТУ):
        смуга = ЧАСТКА_ЗРОСТУ.get(рівень)
        зн.append(dict(_зн("K-OUT-23", "hint",
            "довжина %.0f см = %.0f %% зросту" % (довж, частка * 100), [_імʼя(в)],
            "це ЄДИНЕ місце теми, де «коротка» й «довга» верхня річ переведені в "
            "сантиметри, тобто в те, що фід може нести: коротка дублянка %.0f–%.0f см, "
            "довга %.0f–%.0f см (LuisaViaRoma). На цьому тілі рівень «%s» дає %.0f см%s"
            % (ДУБЛЯНКА_КОРОТКА_СМ[0], ДУБЛЯНКА_КОРОТКА_СМ[1], ДУБЛЯНКА_ДОВГА_СМ[0],
               ДУБЛЯНКА_ДОВГА_СМ[1], рівень, довж,
               ("; частка зросту %.0f %% при смузі джерела %.0f–%.0f %%"
                % (частка * 100, смуга[0] * 100, смуга[1] * 100)) if смуга else ""),
            ламається="джерело дає АБСОЛЮТНІ сантиметри без прив'язки до зросту, тоді "
                      "як для тренча те саме питання описують ЧАСТКОЮ зросту — і "
                      "частка правильніша за побудовою: 55–60 см це 37 %% від 160 см і "
                      "33 %% від 180, тобто «коротка» означає різне на різних людях. "
                      "Джерело комерційне (журнал розкішного рітейлера), число "
                      "фольклорне",
            вимір=довж, поріг=ДУБЛЯНКА_КОРОТКА_СМ[1]),
            сила_нп=0.2,
            сила_нп_джерело="шкала прив'язки, не поріг: правило нічого не відкидає"))
    return зн


def краї(речі, тіло=None):
    """K-OUT-03 (штраф на близькість), K-OUT-04 (каскад інвертує), K-OUT-43 (ремонт
    лише в один бік)."""
    зн = []
    в = _верхній(речі)
    if в is None:
        return зн
    під = [р for р in речі if р.get("слот") in ("сукня", "низ")]
    if not під:
        return зн
    # Розстібнуте пальто ховає нижній край? Ні — навпаки: закрите пальто, яке ПОВНІСТЮ
    # ховає сукню, робить правило беззмістовним (двох видимих країв нема).
    if в.get("стан") == "застібнуто" and в.get("ховає_повністю"):
        return зн
    в_см, в_дж = край_см(в, тіло)
    for р in під:
        н_см, н_дж = край_см(р, тіло)
        if в_см is None or н_см is None:
            continue
        if ДЖ_ДЕФОЛТ in (в_дж, н_дж):
            зн.append(dict(_зн("K-OUT-03", "питання",
                "відстань між краями — довжини нема у фіді", [_імʼя(в), _імʼя(р)],
                "край узято з ДЕФОЛТУ СЛОТА (%s / %s), а не з речі. Порахувати штраф "
                "на цих числах означало б міряти заглушку й видати результат за вимір"
                % (в_дж, н_дж),
                ремонт="запитати довжину пальта й спідниці/сукні — двох чисел досить",
                ламається="це ЧЕРГА НА ВХІД, а не провал: правило працює, входу нема"),
                сила_нп=0.0, сила_нп_джерело="входу нема: довжина не оголошена"))
            continue
        Δ = round(в_см - н_см, 1)
        каскад = _каскад(речі, тіло)
        if abs(Δ) < 1.0:
            # НУЛЬ — НЕЙТРАЛЬНИЙ, І ЦЕ ЗАПИС СПОРУ, А НЕ ВЕРДИКТ.
            зн.append(dict(_зн("K-OUT-03", "питання",
                "краї збігаються точно — джерела сперечаються, і сторону не обрано",
                [_імʼя(в), _імʼя(р)],
                "різниця %.1f см. Autum Love точний збіг ЗАБОРОНЯЄ («читається як "
                "стюардеса»), One Of A Style ПРИПИСУЄ («збіг або довше»), Rue Sophie "
                "ДОЗВОЛЯЄ («точний збіг читається витончено»). Спільне в усіх чотирьох — "
                "заборона МАЙЖЕ-збігу, а не збігу. Доки вердикти не скажуть інше, "
                "точний збіг НЕЙТРАЛЬНИЙ" % Δ,
                ламається="нуль тут — не «добре» і не «погано», а незакрите питання; "
                          "це головний кандидат на калібрування вердиктами"),
                сила_нп=0.0, сила_нп_джерело="спір джерел, сторону не обрано"))
            _СЛ.запис("K-OUT-03", "точний збіг країв — спір", "краї",
                      значення="Δ=%.1f см" % Δ, сила=0.0, напрям="нейтрально")
            continue
        if abs(Δ) >= C["смуга_близькості_см"]:
            continue                       # чиста різниця — правило мовчить
        сила_нп = round(1.0 - abs(Δ) / C["смуга_близькості_см"], 2)
        if каскад:
            # ── K-OUT-04: ОДИН МАЙЖЕ-ЗБІГ — ВИПАДКОВІСТЬ, ТРИ ВПОРЯДКОВАНІ — КАСКАД
            зн.append(dict(_зн("K-OUT-04", "default",
                "оголошений каскад: штраф на близькість інвертується", каскад["речі"],
                "три шари з монотонно зростаючими краями, кожен крок у смузі %.0f–%.0f см "
                "(%s). Це рівно та смуга, яку K-OUT-03 карає, — і саме тому правило "
                "інвертується: один майже-збіг випадковий, три впорядковані читаються "
                "як рішення" % (C["каскад_крок_низ_см"], C["каскад_крок_верх_см"],
                                ", ".join("%.1f см" % к for к in каскад["кроки"])),
                ламається="«навмисність» виводиться З ГЕОМЕТРІЇ. Людина, у якої просто "
                          "є три речі в такому відношенні, дістає кредит за рішення, "
                          "якого не ухвалювала. Неперевірено"),
                сила_нп=0.0, сила_нп_джерело="каскад скасовує штраф, а не помʼякшує"))
            _СЛ.запис("K-OUT-04", "каскад інвертує K-OUT-03", "краї",
                      значення="кроки %s" % каскад["кроки"], сила=0.0, напрям="інверсія")
            continue
        # ── K-OUT-43 + K-OUT-42: НАПРЯМ ПРОВАЛУ ВИРІШУЄ ВСЕ ──────────────────
        # ── ЗНАК БУВ ПЕРЕВЕРНУТИЙ, І ЦЕ ВЕЛО РЕМОНТ У ПРОТИЛЕЖНИЙ БІК ────────
        # ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026).
        # `край_см` віддає висоту краю ВІД ПІДЛОГИ — це його власний докстрінг і
        # це виміряно: на тілі 168 пальто до коліна дає 47.9, сукня максі — 10.1.
        # Отже Δ = в_см − н_см > 0 означає «край верхнього шару ВИЩЕ», тобто
        # верхній шар КОРОТШИЙ. Гілка `if Δ > 0` називала його ДОВШИМ і радила
        # ВКОРОТИТИ вже коротше пальто; дзеркальна гілка казала «ремонту нема»
        # на пальті, яке насправді довше й якраз вкорочується.
        #   before  пальто 60.0 / сукня 53.0 (пальто КОРОТШЕ):
        #           «верхній шар ДОВШИЙ на 7.0 см — бік, який ремонтується»
        #           ремонт: ВКОРОТИТИ верхній шар          ← робить розрив більшим
        #   after   «верхній шар КОРОТШИЙ на 7.0 см — термінальний бік»
        #           ремонт: замінити спідницю/сукню
        # САМІ ТЕКСТИ РЕМОНТІВ ПРАВИЛЬНІ — вони стояли не з того боку, тому
        # правка міняє тільки умову, жодного слова в ремонтах і жодного числа.
        # ЩО ЦЕ НЕ КОНВЕНЦІЯ МОДУЛЯ: K-OUT-05 у цьому ж файлі читає ту саму
        # величину правильно — «if в_см > ж_см: край пальта ВИЩЕ краю жакета =
        # жакет визирає». Тобто помилка локальна, в одній гілці.
        # ЧОМУ БАТАРЕЯ МОВЧАЛА: у навмисному зимовому образі пальто до литки
        # (33.6) над сукнею до коліна (47.9) дає |Δ| = 14.3 ≥ смуги близькості,
        # і правило не спрацьовує взагалі. Гілку не покривав жоден вхід.
        if Δ < 0:                      # край верхнього шару НИЖЧЕ = він ДОВШИЙ
            ремонт = ["ВКОРОТИТИ верхній шар до чистої різниці — це ремонтопридатний "
                      "бік (K-OUT-43: забрати можна, додати не можна)",
                      "ціна названа чесно: вкорочення пальта переносить кишені, лацкани "
                      "й пропорцію застібки — «просто підрубити» тут неправда",
                      "АБО інша річ у слоті верхнього шару"]
            напрям = ("верхній шар ДОВШИЙ на %.1f см — бік, який ремонтується" % abs(Δ))
            _куди = "вкоротити верхній шар"
        else:
            ремонт = ["замінити спідницю/сукню — подовжити пальто НЕМОЖЛИВО нічим "
                      "(K-OUT-43), і це не питання ціни, а питання тканини",
                      "АБО інший верхній шар"]
            напрям = ("верхній шар КОРОТШИЙ на %.1f см — термінальний бік, ремонту нема"
                      % abs(Δ))
            _куди = "змінити низ: подовжити верхній шар нічим не можна"
        # СУТЬ НЕСЕ НАПРЯМ, ЯК ТІЛЬКИ ЗНАК СТАВ ПРАВИЛЬНИЙ. До цієї правки рядок,
        # що доїжджає до ші, був однаковий для обох боків — «краї майже
        # збігаються: 7.0 см», — а бік і ремонт лежали в `чому` й `ремонт`, яких
        # `bridge._стислі_знахідки` не передає. Дописати напрям раніше було не
        # можна: він був перевернутий, і речення понесло б помилку далі.
        зн.append(dict(_зн("K-OUT-03", "strong",
            "краї майже збігаються (%.1f см) — %s" % (abs(Δ), _куди),
            [_імʼя(в), _імʼя(р)],
            "два поділи на одній вертикалі на відстані %.1f см читаються як одна товста "
            "ненавмисна горизонталь, і око не може сказати, чи це задумано. Пʼять "
            "незалежних джерел забороняють САМЕ майже-збіг: «вигляд фартуха» (Collins), "
            "«стюардеса» (Autum Love), «незавершений образ» (Outfit Trends). %s"
            % (abs(Δ), напрям),
            ремонт=ремонт,
            ламається="ширина смуги %.0f см — ОДНЕ джерело, одне кругле число в дюймах "
                      "[конвенція]. І смуга не масштабується зі зростом, хоч це майже "
                      "напевно неправда" % C["смуга_близькості_см"],
            поріг=C["смуга_близькості_см"], вимір=abs(Δ)),
            сила_нп=сила_нп,
            сила_нп_джерело="вимір: (смуга − |Δ|) / смуга, спад у ОБИДВА боки"))
        _СЛ.запис("K-OUT-03", "штраф на близькість країв", "краї",
                  значення="Δ=%.1f см (смуга %.0f)" % (Δ, C["смуга_близькості_см"]),
                  сила=сила_нп, напрям="ремонт %s" % ("є" if Δ < 0 else "нема"))
        # ── K-OUT-43 — ОКРЕМЕ ТВЕРДЖЕННЯ, А НЕ РЯДОК У ЧУЖОМУ РЕМОНТІ ────────
        # Доти воно жило текстом усередині ремонту K-OUT-03 і власного ID не
        # емітувало — тобто гейт досяжності законно рахував його мертвим. Це
        # ОКРЕМА претензія: два симетричні за модулем порушення асиметричні за
        # ремонтопридатністю, і рекомендація мусить це знати, ПЕРШ ніж її давати.
        # ЗНАК ТУТ БУВ ПЕРЕВЕРНУТИЙ І ПІСЛЯ ТОГО, ЯК ЙОГО ВИПРАВИЛИ ВИЩЕ
        # (10.09.2026). Гілку K-OUT-03 перевернули на `Δ < 0`, а цей блок лишився
        # на `Δ > 0` — і дві знахідки з ОДНОГО витка циклу почали радити протилежні
        # дії: на пальті 60.0 над сукнею 53.0 (Δ=+7, пальто КОРОТШЕ) K-OUT-03 казав
        # «замінити спідницю/сукню», а K-OUT-43 поруч — «вкоротити верхній шар».
        # Правка та сама, що й вище: перевернуто ЛИШЕ умови, жодного слова в
        # ремонтах і жодного числа. Тепер Δ < 0 (верхній шар ДОВШИЙ) = бік, який
        # ремонтується (0.5), Δ > 0 (верхній КОРОТШИЙ) = термінальний бік (1.0).
        зн.append(dict(_зн("K-OUT-43", "default",
            "порушення %s" % ("РЕМОНТУЄТЬСЯ: вкоротити" if Δ < 0
                              else "ТЕРМІНАЛЬНЕ: подовжити виріб не можна"),
            [_імʼя(в)],
            "додати довжину виробу НЕ МОЖНА; поділ і рукав вкорочуються, а рукав ще й "
            "подовжується за наявності запасу. Тому пальто на %.1f см %s за поділ під "
            "ним %s"
            % (abs(Δ), "довше" if Δ < 0 else "коротше",
               "вкорочується до чистої різниці" if Δ < 0
               else "не лікується нічим, крім заміни спідниці чи сукні"),
            ремонт=(["вкоротити верхній шар"] if Δ < 0
                    else ["інша річ у слоті нижнього краю"]),
            ламається="вкорочення пальта ПЕРЕНОСИТЬ кишені, лацкани й пропорцію "
                      "застібки, тож «просто підрубити» — неправда для верхнього шару "
                      "так само, як для жакета. Вартості джерела не називають, а вона "
                      "й вирішує, чи це реальна опція. Для дублянки, хутра й пуховика "
                      "вкорочення взагалі інша операція"),
            сила_нп=0.5 if Δ < 0 else 1.0,
            сила_нп_джерело="напрям провалу, не модуль: асиметрія, а не симетрія"))
        _СЛ.запис("K-OUT-43", "напрям провалу вирішує ремонтопридатність", "краї",
                  значення="Δ=%+.1f" % Δ, сила=1.0 if Δ > 0 else 0.5,
                  напрям="асиметрія ремонту")
    return зн


# ── ПОРЯДОК ШАРІВ У КАСКАДІ — УМОВА, А НЕ МОВЧАЗНЕ ПРИПУЩЕННЯ (Н-outer-1-074) ─
# `краї_.sort()` робить послідовність монотонною ЗАВЖДИ, тож «монотонно зростаючі
# краї» ніколи нічого не відсіювали: перевіряється КРОК і — тепер — ПОРЯДОК ШАРІВ.
# Каскад читається як рішення тільки коли зовнішній шар НАЙДОВШИЙ: пальто, з-під
# якого визирає кардиган, з-під якого блуза. Перевернутий порядок (пальто коротше
# за те, що під ним) — це рівно та поломка, яку K-OUT-03 карає штрафом, а старий
# `_каскад` зараховував її як «оголошений каскад» і штраф СКАСОВУВАВ.
# Константа іменована навмисно: якщо власник вирішить, що три внутрішні шари теж
# утворюють каскад, це буде видима зміна одного значення, а не мовчазна умова.
КАСКАД_ЗОВНІШНІЙ_НАЙДОВШИЙ = True
КАСКАД_СЛОТИ = ("верх", "верхній_шар", "сукня")


def _каскад(речі, тіло):
    """K-OUT-04. Три і більше шари, кожен крок у смузі 2–5 см, і ЗОВНІШНІЙ ШАР
    НАЙДОВШИЙ. Два шари каскаду не утворюють — нема напрямку, який можна прочитати.

    Монотонність тут НЕ перевіряється: її забезпечує `краї_.sort()`. Перевіряються
    рівно дві речі — КРОК між сусідніми краями і ПОРЯДОК ШАРІВ (найнижчий край,
    тобто найдовша річ, мусить лежати у слоті «верхній_шар»)."""
    краї_ = []
    for р in речі:
        if р.get("слот") not in КАСКАД_СЛОТИ:
            continue
        см, дж = край_см(р, тіло)
        if см is None or дж == ДЖ_ДЕФОЛТ:
            return None
        краї_.append((см, _імʼя(р), р.get("слот")))
    if len(краї_) < 3:
        return None
    краї_.sort()
    if КАСКАД_ЗОВНІШНІЙ_НАЙДОВШИЙ and краї_[0][2] != "верхній_шар":
        return None
    кроки = [round(краї_[i + 1][0] - краї_[i][0], 1) for i in range(len(краї_) - 1)]
    if all(C["каскад_крок_низ_см"] <= к <= C["каскад_крок_верх_см"] for к in кроки):
        return dict(речі=[n for _, n, _с in краї_], кроки=кроки)
    return None
