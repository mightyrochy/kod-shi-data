# R-COL-12 — дубль `colorspace.c_max_поверхня`: хрома нормується стелею реальної поверхні.
def c_max_поверхня(L, h):
    """(стеля, джерело). Стеля хроми для ФАРБОВАНОЇ ПОВЕРХНІ на цьому вузлі.

    Джерело — чесно: "Pointer 1980, адаптовано C→D65 (Bradford)" — вузол таблиці
    після зміни освітлювача (не «виміряний Pointer»: виміряне число стоїть у
    `_POINTER_ВУЗЛИ_C`); "sRGB — поза сіткою Pointer" — фолбек за межами L* 15–90.
    Викликач зобов'язаний показати джерело: інакше стеля дисплея піде під іменем
    тканини."""
    h = h % 360
    ключ = (int(round(L/5.0))*5, int(round(h/10.0))*10 % 360)
    if ключ in _POINTER_ВУЗЛИ:
        return _POINTER_ВУЗЛИ[ключ], "Pointer 1980, адаптовано C→D65 (Bradford)"
    return c_max(L, h), ("sRGB — поза сіткою Pointer (L* 15–90): стеля реальних поверхонь "
                         "тут не виміряна")

def у_фантомній_зоні(L, h):
    """Чи вузол лежить у задокументованій зоні фантомних вікон (R-COL-12)."""
    h = h % 360
    return (_ФАНТОМНА_ЗОНА["L"][0] <= L <= _ФАНТОМНА_ЗОНА["L"][1]
            and _ФАНТОМНА_ЗОНА["h"][0] <= h <= _ФАНТОМНА_ЗОНА["h"][1])

def same_colour(lab1, lab2, tol=3.0):
    """Інжест каталогу: чи це той самий колір (ΔE00, зона валідності <5)."""
    d=de00(lab1,lab2)
    return dict(same=d<=tol, dE00=round(d,2), note="ΔE00 надійна лише для малих різниць")

# ── R-PC-09: допуск на ШКІРУ мусить масштабуватись зі світлотою шкіри ───────
# Тема-2, R-PC-09 · T2 · default. Скалярний допуск ΔE00 на «той самий колір шкіри»
# систематично СУВОРІШИЙ до темної шкіри — приблизно в 1.5–1.7 раза.
#
# Джерело чисел (через R-PC-04): Paravina та ін., пороги колірної різниці щелепно-
# лицевих реплікацій шкіри (PubMed 19432759) — 45 спостерігачів, 30 пар силіконових
# зразків кольору шкіри, контрольований бокс, пороги 50:50%.
#   помітність:    0.7 (світла) / 1.2 (темна)  -> ×1.71
#   прийнятність:  2.1 (світла) / 3.1 (темна)  -> ×1.48
#
# ЧОМУ ЦЕ ПОСИЛЮЄ, А НЕ ПОСЛАБЛЮЄ R-PC-04: розрив ВИЖИВАЄ спектрофотометр і
# переглядовий бокс. Отже це не лише артефакт камери, і єдиний скалярний допуск на всі
# тони шкіри є систематично суворішим до темної.
#
# ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after): два зчитування обличчя темношкірої людини
# частіше називались «різними», ніж два зчитування світлошкірої, — суто через допуск.
# Після: допуск росте зі спаданням L*, і прапорець впевненості це відображає.
#
# ЩО ІМПОРТОВАНО, А ЩО НІ: імпортовано ВІДНОШЕННЯ (×1.5–1.7), не абсолютні числа —
# так велить сам корпус. Силікон не шкіра: нема просвічування, підповерхневого
# розсіювання, себуму, волосся; протезна література ставить строгішу задачу, ніж
# «чи лестить річ». Тому базовий допуск лишається наш, а зі світлотою міняється
# лише МНОЖНИК.
# ДЕ ЛАМАЄТЬСЯ: під телефонною камерою реальне відношення, ймовірно, БІЛЬШЕ — похибка
# видобування теж росте на темній шкірі. Тобто ця корекція — ПІДЛОГА, не повне
# виправлення, і жорсткого гейту R-PC-04 вона не знімає.
_ШКІРА_L_СВІТЛА, _ШКІРА_L_ТЕМНА = 66.0, 35.0   # опорні точки шкали
_ШКІРА_МНОЖНИК_ТЕМНОЇ = 1.6                    # середина 1.48–1.71, T2

def допуск_шкіри(L_шкіри, база=3.0):
    """(допуск, множник, чому). Допуск ΔE00 на «той самий колір шкіри» для цієї
    світлоти. Множник неперервний між опорними точками — не сходинка: сходинка
    зробила б із світлоти категорію, а вона вимір."""
    if L_шкіри is None:
        return база, 1.0, ("світлоти шкіри нема — множник 1.0. Це НЕ нейтральний "
                           "вибір: на темній шкірі він відтворює саме ту нерівність, "
                           "яку правило знімає (R-PC-09)")
    t = (float(_ШКІРА_L_СВІТЛА) - float(L_шкіри)) / (_ШКІРА_L_СВІТЛА - _ШКІРА_L_ТЕМНА)
    t = max(0.0, min(1.0, t))
    м = 1.0 + t * (_ШКІРА_МНОЖНИК_ТЕМНОЇ - 1.0)
    return (round(база * м, 2), round(м, 3),
            "допуск ×%.2f: шкіра L*%.1f. Пороги Paravina та ін. на темних зразках "
            "у ~1.5–1.7 раза вищі за світлі, і розрив виживає спектрофотометр — "
            "тобто це не артефакт камери. Імпортовано ВІДНОШЕННЯ, не абсолютні "
            "числа (силікон ≠ шкіра)" % (м, float(L_шкіри)))

