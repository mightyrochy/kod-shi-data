# R-MUN-04 — дубль `colorspace.c_max`: стеля хроми — функція і hue, і value (тіло асиметричне).
def c_max(L, h, space="sRGB"):
    """Стеля хроми C* гамуту `space` на цій світлоті й тоні: двійковий пошук (40 ітерацій у 0..250)
    найбільшого C, за якого `to_rgb` лишається в [0, 1]; кеш за точним вузлом (L, h, space).

    Чому так: R-MUN-04 — стеля хроми залежить і від тону, і від світлоти (тіло гамуту
    асиметричне); це стеля ЕКРАНА, стеля реальної поверхні — `c_max_поверхня`
    (Pointer, R-COL-12). Кеш — швидкість (17.09.2026: 44 415 викликів, 1.78 млн
    `to_rgb` на живому шляху); ключ без округлення, стеля словника 200 000."""
    ключ = (L, h, space)
    v = _КЕШ_C_MAX.get(ключ)
    if v is not None:
        return v
    ar,br=math.cos(math.radians(h)),math.sin(math.radians(h)); lo,hi=0.,250.
    for _ in range(40):
        m=(lo+hi)/2
        if all(-1e-9<=c<=1+1e-9 for c in to_rgb(L,m*ar,m*br,space)): lo=m
        else: hi=m
    if len(_КЕШ_C_MAX) < 200000:
        _КЕШ_C_MAX[ключ] = lo
    return lo

