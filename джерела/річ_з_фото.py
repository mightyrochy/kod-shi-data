    L, C_, h = cs.lch(tuple(lab))
    в = П["вікна"]
    чL = cs.soft(L, в["L"][0], в["L"][1], ШИРИНА_L)
    if нейтраль(tuple(lab)) is not None:
        сила, чC, чh = чL, None, None
        роль = "темна нейтраль" if L < 35 else ("світла нейтраль" if L > 80 else "нейтраль")
        сім = "нейтраль"
    else:
        чC = cs.soft(C_, в["C"][0], в["C"][1], ШИРИНА_C)
        дуги = [д for сім_, дд in в["сім_ї"].items() if сім_ != "очі" for д in дд]
        чh = _дуга_членство(h, дуги)
        очі = _дуга_членство(h, в["сім_ї"].get("очі") or [])
