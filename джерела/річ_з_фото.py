def _дуга_членство(h, дуги):
    """Сила належності кута тону до найближчої з дуг: 1 усередині, далі — м'яке плече."""
    найкр = 0.0
    for д in дуги or ():
        a, b = float(д[0]), float(д[1])
        всередині = (a <= h <= b) if a <= b else (h >= a or h <= b)
        if всередині:
            return 1.0
        відст = min(min(abs(h - a), 360 - abs(h - a)), min(abs(h - b), 360 - abs(h - b)))
        найкр = max(найкр, min(1.0, 2.0 * cs.soft(відст, -1e9, 0.0, ШИРИНА_H)))
    return найкр


def членство_в_палітрі(lab, П):
    """K-PAL-17: {сила, роль, стан, частки, сім_я} кольору речі в практиковій палітрі жінки."""
