def коди_полів():
    """Дозволені коди полів речі для англійського промпта: {поле: [коди]}."""
    import внутрішня_мова as _ВМ
    вих = {п: [к for к, ключ in _ВМ.ТАБЛИЦЯ[т].items() if ключ in словник]
           for п, (т, словник) in _ТАБЛИЦІ_ПОЛІВ.items()}
    вих["owner"].append(_ВМ.UNKNOWN)
    вих["cut"] = list(КРОЇ)
    вих["length"] = list(_довжини_кодів())
    вих["pattern"] = [к for к, ключ in _ВМ.ТАБЛИЦЯ["pattern"].items() if ключ in ПРИНТИ or ключ == "solid"]
    вих["formality"] = list(_БР.ЧИСЛО_ЩАБЛЯ)
    return вих


def ключ_поля(поле, код):
    """Код моделі → слово словника поля (ключ ядра) або None: чужий код не підставляється."""
    import внутрішня_мова as _ВМ
    if _ВМ.невідомо(код):
        return None
    к = str(код).strip()
    if поле in _ТАБЛИЦІ_ПОЛІВ:
        т, словник = _ТАБЛИЦІ_ПОЛІВ[поле]
        ключ = _ВМ.ключ(т, к)
        return ключ if ключ in словник else None
    if поле == "cut":
        return к if к in КРОЇ else None
    if поле == "length":
        return _довжини_кодів().get(к)
    if поле == "pattern":
        ключ = _ВМ.ключ("pattern", к)
        ключ = "однотонний" if ключ == "solid" else ключ
        return ключ if ключ in ПРИНТИ else None
    return None


def код_поля(поле, ключ):
    """Слово словника поля → код внутрішньої мови або None (зворотний бік `ключ_поля`)."""
    if ключ in (None, ""):
        return None
    for к in коди_полів().get(поле, ()):
        if ключ_поля(поле, к) == ключ:
            return к
    return None


def _слово(v, дозволені):
    """Слово моделі → слово зі словника або None: чуже слово не підставляється сусіднім."""
    с = " ".join(str(v or "").replace("_", " ").split()).lower()
    if not с or с in ("null", "none", "невідомо", "—", "-"):
        return None
    # обидва боки — тією самою нормою: «верхній_шар» словника й «верхній шар» моделі — одне слово
    за_низом = {" ".join(str(x).replace("_", " ").split()).lower(): x for x in дозволені}
    return за_низом.get(с)


def _рамка(v):
    """{ліво, верх, право, низ} у тисячних → dict, або None, коли рамка не рамка.

    Приймає й список [ліво, верх, право, низ] — ту форму, якою модель часто відповідає
    попри схему. Межі впорядковуються й затискаються в 0–1000; рамка, тонша за 2 %
    кадру з будь-якого боку, — не річ, а промах, і міряється тоді весь кадр."""
    if isinstance(v, (list, tuple)) and len(v) == 4:
        v = dict(ліво=v[0], верх=v[1], право=v[2], низ=v[3])
    if not isinstance(v, dict):
        return None
    try:
        л, в_, п, н = (float(v.get(k)) for k in ("ліво", "верх", "право", "низ"))
    except (TypeError, ValueError):
        return None
    л, п = sorted((max(0.0, min(1000.0, л)), max(0.0, min(1000.0, п))))
    в_, н = sorted((max(0.0, min(1000.0, в_)), max(0.0, min(1000.0, н))))
    if п - л < 20 or н - в_ < 20:
        return None
    return dict(ліво=round(л), верх=round(в_), право=round(п), низ=round(н))


