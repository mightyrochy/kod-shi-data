def пом_якшення(в):
    """Вердикт → що РЕШТА образу робить, щоб пом'якшити (п.5 наряду, «без замків»).

    Річ, що «не личить», усе одно стоїть у кожному образі: явний вибір жінки сильніший за
    гейт коду. Код лише прибудовує решту — вимогами пакета (`моделі`), — і каже це одним
    м'яким ПОВІДОМЛЕННЯМ (`повідомлення`) на картці під її річчю. «Личить» — нічого
    пом'якшувати.

    Ч-1 (26.09.2026, п.12): доти поле звалось `жінці` й було готовою фразою («Цю річ ти
    обрала сама, тож вона в кожному образі. Щоб її пом'якшити: …»). Тепер це заяви кодами,
    а речення складає мовна модель. Разом із фразою пішов і зшивач повторів «біля обличчя —
    …; біля обличчя — …»: два рази те саме — це вже не дві заяви, а одна, і код не мусить
    вирізати повтор із тексту, якого не писав."""
    решті = [tuple(x) for x in ((в or {}).get("решті") or [])]
    if (в or {}).get("колір") == БЕЗ_КОЛЬОРУ and (not решті or (в or {}).get("рівень") == "личить"):
        # річ словами без кольору (рядок 157): на картці під нею — що колір не звірено
        return dict(моделі=[], повідомлення=_ВМ.повідомлення(
            "her_item_softening", _ВМ.заява("colour_unknown_rest_not_matched")))
    if not решті or (в or {}).get("рівень") == "личить":
        return dict(моделі=[], повідомлення=None)
    # ПОРАДА, А НЕ ЗВІТ ПРО ЗРОБЛЕНЕ: заяви стоять на картках усіх рук, а руки без коду (3–4)
    # вимог пакета не бачили — «решту дібрано так» там було б неправдою й видавало б руку
    заяви, бачені = [], set()
    for _м, ж in решті[:2]:
        код, знач = ж if isinstance(ж, tuple) else (ж, None)
        if код in бачені:       # та сама заява двічі — це одна заява
            continue
        бачені.add(код)
        заяви.append(_ВМ.заява(код, **(знач or {})))
    return dict(моделі=[м for м, _ж in решті],
                повідомлення=_ВМ.повідомлення("her_item_softening",
                                              _ВМ.заява("her_item_in_every_look"), *заяви))


