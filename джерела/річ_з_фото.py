def пом_якшення(в):
    """Вердикт → що РЕШТА образу робить, щоб пом'якшити (п.5 наряду, «без замків»).

    Річ, що «не личить», усе одно стоїть у кожному образі: явний вибір жінки сильніший за
    гейт коду. Код лише прибудовує решту — вимогами пакета (`моделі`), — і каже це одним
    м'яким рядком (`жінці`) на картці під її річчю. «Личить» — нічого пом'якшувати."""
    решті = [tuple(x) for x in ((в or {}).get("решті") or [])]
    if (в or {}).get("колір") == БЕЗ_КОЛЬОРУ and (not решті or (в or {}).get("рівень") == "личить"):
        # річ словами без кольору (рядок 157): на картці під нею — що колір не звірено
        return dict(моделі=[], жінці="Колору цієї речі я не знаю — фото нема, і колір ти не назвала, "
                                     "тож решту образу з нею за кольором не звіряла.")
    if not решті or (в or {}).get("рівень") == "личить":
        return dict(моделі=[], жінці=None)
    # ПОРАДА, А НЕ ЗВІТ ПРО ЗРОБЛЕНЕ: рядок стоїть на картках усіх рук, а руки без коду (3–4)
    # вимог пакета не бачили — «решту дібрано так» там було б неправдою й видавало б руку
    ж = [ж for _м, ж in решті[:2]]
    if len(ж) == 2 and " — " in ж[1] and ж[0].split(" — ")[0] == ж[1].split(" — ")[0]:
        ж[1] = ж[1].split(" — ", 1)[1]        # «біля обличчя — …; біля обличчя — …» без повтору
    return dict(моделі=[м for м, _ж in решті],
                жінці="Цю річ ти обрала сама, тож вона в кожному образі. Щоб її пом'якшити: %s."
                      % "; ".join(ж))


БЕЗ_КОЛЬОРУ = "нема ні виміру, ні слова кольору"     # `вердикт.колір`, коли колір не відомий


def _рядок_жінці(рівень, фрази, типова_нагода):
    """Вердикт словами: личить / личить з умовою / краще інша — і чому, одним-двома реченнями."""
    почин = {"личить": "Личить", "з умовою": "Личить з умовою", "краще інша": "Краще інша"}[рівень]
    суть = "; ".join(фрази[:2])
    р = почин + (": " + суть if суть else "") + "."
    if рівень == "краще інша":
        р += " Зібрати з нею все одно можна — решту доберу так, щоб пом'якшити."
    if типова_нагода:
        р += " Нагоди ти не назвала — дивлюсь на звичайний день."
    return р


