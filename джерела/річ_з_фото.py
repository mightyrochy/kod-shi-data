def для_моделі(річ):
    """Річ з фото для «паспорта досі» в промпті: слова, без чисел виміру.

    Модель бачить колір СЛОВОМ ВИМІРУ, коли код уже поміряв (свідок сильніший за її
    перше слово), і вердикт коду реченням, яке вона переказує. Lab, hex і рамка до неї не
    їдуть: вона компонує й говорить словами, а числа — внутрішня шкала коду."""
    в = {k: річ.get(k) for k in ("ід", "фото", "назва", "слот", "колір", "матеріал", "крій",
                                 "довжина", "принт", "ошатність", "чия")
         if річ.get(k) not in (None, "", [])}
    вим = річ.get("вимір") or {}
    if вим.get("слово"):
        в["колір"] = вим["слово"]
    ве = річ.get("вердикт") or {}
    if ве.get("рядок"):
        в["вердикт_коду"] = ве["рядок"]
    if річ.get("закріплена") is not None:
        в["у_кожному_образі"] = bool(річ.get("закріплена"))
    return в


