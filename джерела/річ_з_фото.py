def _слово(v, дозволені):
    """Слово моделі → слово зі словника або None: чуже слово не підставляється сусіднім."""
    с = " ".join(str(v or "").replace("_", " ").split()).lower()
    if not с or с in ("null", "none", "невідомо", "—", "-"):
        return None
    # обидва боки — тією самою нормою: «верхній_шар» словника й «верхній шар» моделі — одне слово
    за_низом = {" ".join(str(x).replace("_", " ").split()).lower(): x for x in дозволені}
    return за_низом.get(с)


def _рамка(v):
    """{ліво, верх, право, низ} у тисячних → dict, або None, коли рамка не рамка.

    Приймає й список [ліво, верх, право, низ] — ту форму, якою модель часто відповідає
    попри схему. Межі впорядковуються й затискаються в 0–1000; рамка, тонша за 2 %
    кадру з будь-якого боку, — не річ, а промах, і міряється тоді весь кадр."""
    if isinstance(v, (list, tuple)) and len(v) == 4:
        v = dict(ліво=v[0], верх=v[1], право=v[2], низ=v[3])
    if not isinstance(v, dict):
        return None
    try:
        л, в_, п, н = (float(v.get(k)) for k in ("ліво", "верх", "право", "низ"))
    except (TypeError, ValueError):
        return None
    л, п = sorted((max(0.0, min(1000.0, л)), max(0.0, min(1000.0, п))))
    в_, н = sorted((max(0.0, min(1000.0, в_)), max(0.0, min(1000.0, н))))
    if п - л < 20 or н - в_ < 20:
        return None
    return dict(ліво=round(л), верх=round(в_), право=round(п), низ=round(н))


def _канон(о, фото_ід):
    """Один обʼєкт моделі → поля речі за словниками; незнайоме слово — None, не здогад."""
    try:
        ош = int(round(float(о.get("ошатність"))))
        ош = ош if 1 <= ош <= 10 else None
    except (TypeError, ValueError):
        ош = None
    return dict(фото=фото_ід,
                назва=(" ".join(str(о.get("назва") or "").split())[:80] or None),
                слот=_слово(о.get("слот"), СЛОТИ_РЕЧІ),
                колір=_слово(о.get("колір"), КОЛЬОРИ),
                матеріал=_слово(о.get("матеріал"), МАТЕРІАЛИ),
                крій=_слово(о.get("крій"), КРОЇ),
                довжина=_слово(о.get("довжина"), ДОВЖИНИ),
                принт=_слово(о.get("принт"), ПРИНТИ),
                ошатність=ош,
                чия=(_слово(о.get("чия"), ЧИЯ) or "невідомо"),
                рамка=_рамка(о.get("рамка")))


def речі_з_json(сирі, фото=None, досі=None, словами=None):
    """Поле `речі_з_фото` відповіді моделі → канонічні речі, злиті з паспортом досі.

    ІДЕНТИФІКАТОР РЕЧІ СТАВИТЬ КОД: `ід` = ід фото, а друга й третя річ на тому самому
    фото дістають суфікс («ф1·2»). Модель не нумерує речей — інакше перейменування між
    ходами розмови відривало б вимір і вердикт від речі.
    ЗЛИТТЯ ПОКЛЮЧОВЕ, А НЕ ЗАМІНА: речі досі лишаються, навіть коли модель їх не
    повернула (річ зникає з розмови лише рукою жінки); описові поля моделі свіжіші за
    старі, поля коду (`ПОЛЯ_КОДУ`) модель не переписує ніколи. Нове фото, про яке модель
    не сказала нічого, не губиться: річ стоїть із порожнім описом і міряється цілим
    кадром — «без входу: слот» чесніше, ніж зникле фото.

    `словами` — `речі_словами(слова)` (рядок 157): лише тоді річ без фото приймається —
    ід «с1», колір — слово, виміру нема й це сказано у вердикті."""
    досі = [dict(р) for р in (досі or []) if isinstance(р, dict) and р.get("ід")]
    за_ід = {р["ід"]: р for р in досі}
    відомі_фото = {str(ф.get("ід")) for ф in (фото or []) if ф.get("ід")} | {р.get("фото") for р in досі}
    нові_фото = [str(ф.get("ід")) for ф in (фото or []) if ф.get("ід")]
    лічба = {}
    for р in досі:
        лічба[р.get("фото")] = лічба.get(р.get("фото"), 0) + 1
    вих = list(досі)
    бачені_нові = set()
    for о in (сирі if isinstance(сирі, list) else []):
        if not isinstance(о, dict):
            continue
        фото_ід = str(о.get("фото") or "").strip()
        # РІЧ СЛОВАМИ (рядок 157): без фото, лише коли код сам упізнав у її словах її річ
        # (`словами`); ід «с1», «с2» ставить код, та сама річ — той самий слот
        if not фото_ід and словами:
            к = _канон(о, None)
            if not к["слот"] or к["слот"] not in {д["слот"] for д in словами if д["стан"] != "відмова"}:
                continue
            к["чия"] = "моя"
            стара = next((р for р in вих if not р.get("фото") and р.get("слот") == к["слот"]), None)
            if стара is not None:
                for k, v in к.items():
                    if k not in ПОЛЯ_КОДУ and v not in (None, ""):
                        стара[k] = v
                continue
            н = 1 + sum(1 for р in вих if not р.get("фото"))
            вих.append(dict(к, ід="с%d" % н))
            continue
        if фото_ід not in відомі_фото:
            # Модель не назвала фото (одне фото в репліці — однозначно його) — або назвала
            # чуже. Друге не зараховується: річ без фото нема чим міряти.
            if len(нові_фото) == 1 and not фото_ід:
                фото_ід = нові_фото[0]
            else:
                continue
        к = _канон(о, фото_ід)
        # Річ досі на тому самому фото з тим самим слотом — це ТА САМА річ, оновлена.
        стара = next((р for р in досі if р.get("фото") == фото_ід
                      and (р.get("слот") == к["слот"] or not р.get("слот"))), None)
        if стара is not None:
            for k, v in к.items():
                if k not in ПОЛЯ_КОДУ and v not in (None, ""):
                    стара[k] = v
            continue
        if фото_ід not in нові_фото:
            continue                   # нову річ на старому фото модель вигадати не може
        лічба[фото_ід] = лічба.get(фото_ід, 0) + 1
        ід = фото_ід if лічба[фото_ід] == 1 else "%s·%d" % (фото_ід, лічба[фото_ід])
        бачені_нові.add(фото_ід)
        вих.append(dict(к, ід=ід))
    for фото_ід in нові_фото:
        if фото_ід not in бачені_нові and not any(р.get("фото") == фото_ід for р in вих):
            вих.append(dict(_канон({}, фото_ід), ід=фото_ід))
    # «ПЕВНА» РІЧ СЛОВАМИ НЕ ЗАЛЕЖИТЬ ВІД ТОГО, ЧИ МОДЕЛЬ ЇЇ ПОВЕРНУЛА (рядок 157): річ стоїть у
    # паспорті іменною групою з її ж клаузи, а колір лишається «без входу», поки вона чи
    # модель не назвали його словом. «Непевну» ставить лише модель; «відмова» не ставиться.
    # Той самий слот уже несе річ із фото — це та сама річ, другої не треба.
    for д in (словами or []):
        if д["стан"] == "відмова":
            # пізніша відмова знімає її ж річ словами (фото-речі знімає лише її рука)
            вих = [р for р in вих if р.get("фото") or р.get("слот") != д["слот"]]
        elif д["стан"] == "певна" and not any(р.get("слот") == д["слот"] for р in вих):
            вих.append(dict(_канон({}, None), слот=д["слот"], назва=д["назва"], чия="моя",
                            ід="с%d" % (1 + sum(1 for р in вих if not р.get("фото")))))
    вих = [р for р in вих if р.get("фото") or not any(
        х.get("фото") and х.get("слот") == р.get("слот") for х in вих)]
    return закріпити(вих)


# ═══════════ 3. ЗАКРІПЛЕННЯ: ЯКА РІЧ СТОЇТЬ У КОЖНОМУ ОБРАЗІ ═══════════════════════
# Слоти, що займають одне й те саме місце в структурі образу: сукня й комплект замінюють
# пару верх+низ (`outfit.елементи`, `pipeline._ТРЕТЯ`), тож дві закріплені речі з таких
# слотів в одному образі не стоять. Той самий слот — тим паче.
_ЗАЙМАЄ = {"сукня": {"сукня", "комплект", "верх", "низ"},
           "комплект": {"сукня", "комплект", "верх", "низ"},
           "верх": {"верх", "сукня", "комплект"},
           "низ": {"низ", "сукня", "комплект"}}


def займає(слот):
    """Слоти, які річ цього слота робить зайнятими в образі (сама — завжди)."""
    return set(_ЗАЙМАЄ.get(слот) or ()) | ({слот} if слот else set())


def закріпити(речі):
    """Позначити, які речі стоять у КОЖНОМУ образі руки 1: `закріплена` True/False.

    Правило одне: закріплюється кожна річ зі слотом, поки вона не конфліктує з ПІЗНІШОЮ
    (свіжіша репліка — свіжіше питання). Конфлікт — той самий слот або структурне місце
    (`займає`: сукня проти верху). Річ, що програла, лишається в паспорті з причиною
    `чому_не_закріплена`: вердикт «чи підійде» вона дістає так само. Явне «не збирати з
    нею» — рука жінки (`закріплена: False` із показу) — переважає і не перебивається.
    Річ без слота не закріплюється: у пулі їй нема місця, і це сказано причиною."""
    зайняті = set()
    for р in reversed(речі):
        if р.get("рука") == "не закріплювати":
            р["закріплена"], р["чому_не_закріплена"] = False, "ти сказала не збирати з нею"
            continue
        сл = р.get("слот")
        if not сл:
            р["закріплена"], р["чому_не_закріплена"] = False, "не зрозуміла, яка це річ (слот)"
            continue
        if займає(сл) & зайняті:
            р["закріплена"] = False
            р["чому_не_закріплена"] = "у цьому місці образу вже стоїть пізніша річ з фото"
            continue
        р["закріплена"] = True
        р.pop("чому_не_закріплена", None)
        зайняті |= займає(сл)
    return речі


def закріплені(речі):
    """Речі з фото, що стоять у кожному образі (порядок — як у паспорті)."""
    return [р for р in (речі or []) if isinstance(р, dict) and р.get("закріплена") and р.get("слот")]


# ═══════════ 4. ВИМІР КОЛЬОРУ ПІКСЕЛЯМИ ══════════════════════════════════════════
# АЛГОРИТМ — ЖНИВ V2 БЕЗ SAM, ЧИСЛА — ЇХНІ Ж (наряд рядка 152: «тло й шкіру відрізати так
# само, як це робить жнива v2 без SAM: `маска_без_людини`»). Тло — медіана смуги по
# краях кадру (кадру, вирізаного за рамкою моделі), річ — пікселі далі за `ПОРІГ_ТЛА`
# від неї; відкриття й закриття прибирають шум; лишається найбільша зв'язна пляма; менша
# за 1 % кадру — не річ. ЧОГО ТУТ НЕМА ПРОТИ ЖНИВ: карти ATR (парсер тіла живе на
# ноутбуці, у Pyodide його нема), тож шкіра відрізається не семантикою, а її ВЛАСНИМ
# кольором із профілю: піксель ближчий до її шкіри за `ШКІРА_ΔE` — шкіра. Коли це з'їло б
# більше половини плями, річ і є кольору шкіри, і шкіра не відрізається (сказано в `чому`).
МАКС_СТОРОНА = 128        # показ вирізає рамку й зменшує кадр до цієї сторони (`пікселіРечіП`)
ПОРІГ_ТЛА = 28.0          # = жнива_маски.маска_без_людини: відстань RGB від медіани рамки кадру
МІН_ЧАСТКА = 0.01         # = жнива_маски.МІН_ЧАСТКА_ЗАПАСНОЇ: менше — шум на краях тла, не річ
ШКІРА_ΔE = 12.0           # T3: піксель ближчий до її шкіри (ΔE76 у Lab) — шкіра, не річ
К_КЛАСТЕРІВ = 4           # = жнива_колір.виміряти_колір (k=4)
ВИБІРКА = 3000            # пікселів плями для k-means (жнива: 20 000 із кадру 1024 px)
СІД = 17                  # = жнива_колір.виміряти_колір (сід=17): вимір відтворюваний


def розпакувати(пікселі):
    """{дані: base64(url) RGB-байтів рядок за рядком, ширина, висота} → (w, h, [(r, g, b)…]).

    Показ шле рівно три байти на піксель без альфи (`пікселіРечіП`). Довжина, що не
    сходиться з w·h·3, — не той вхід, і вимір не робиться (ValueError летить у виклик)."""
    w, h = int(пікселі["ширина"]), int(пікселі["висота"])
    с = str(пікселі["дані"])
    сирі = _b64.urlsafe_b64decode(с + "=" * (-len(с) % 4))
    if w <= 0 or h <= 0 or len(сирі) != w * h * 3:
        raise ValueError("пікселі речі: %d байт на %d×%d" % (len(сирі), w, h))
    return w, h, [tuple(сирі[i:i + 3]) for i in range(0, len(сирі), 3)]


def _медіана(xs):
    """Медіана списку чисел (порожній — 0)."""
    s = sorted(xs)
    if not s:
        return 0.0
    m = len(s) // 2
    return float(s[m]) if len(s) % 2 else (s[m - 1] + s[m]) / 2.0


def _рамка_кадру(w, h):
    """Індекси пікселів смуги по краях кадру — тієї самої ширини, що в жнивах (1/40 сторони)."""
    к = max(2, min(w, h) // 40)
    return [y * w + x for y in range(h) for x in range(w)
            if x < к or x >= w - к or y < к or y >= h - к]


def _морфологія(m, w, h, ерозія):
    """Один крок ерозії (ерозія=True) або дилатації 3×3 над булевою маскою."""
    вих = [False] * (w * h)
    for y in range(h):
        for x in range(w):
            сусіди = [m[yy * w + xx] for yy in range(max(0, y - 1), min(h, y + 2))
                      for xx in range(max(0, x - 1), min(w, x + 2))]
            вих[y * w + x] = all(сусіди) if ерозія else any(сусіди)
    return вих


def _найбільша_пляма(m, w, h):
    """Лише найбільша 8-зв'язна пляма маски (решта — False)."""
    мітка = [0] * (w * h)
    найб, розмір_найб, n = 0, 0, 0
    for старт in range(w * h):
        if not m[старт] or мітка[старт]:
            continue
        n += 1
        стос, розмір = [старт], 0
        мітка[старт] = n
        while стос:
            i = стос.pop()
            розмір += 1
            y, x = divmod(i, w)
            for yy in range(max(0, y - 1), min(h, y + 2)):
                for xx in range(max(0, x - 1), min(w, x + 2)):
                    j = yy * w + xx
                    if m[j] and not мітка[j]:
                        мітка[j] = n
                        стос.append(j)
        if розмір > розмір_найб:
            найб, розмір_найб = n, розмір
    return [мітка[i] == найб and найб > 0 for i in range(w * h)]


def маска(rgb, w, h, шкіра_lab=None):
    """(маска, частка кадру, чому) — пляма речі без тла й без її шкіри."""
    рамка = _рамка_кадру(w, h)
    тло = tuple(_медіана([rgb[i][к] for i in рамка]) for к in range(3))
    m = [_math.sqrt(sum((p[к] - тло[к]) ** 2 for к in range(3))) > ПОРІГ_ТЛА for p in rgb]
    чому = ["тло від країв кадру"]
    if шкіра_lab is not None:
        шк = [i for i, v in enumerate(m) if v
              and _math.dist(cs.to_lab(rgb[i]), шкіра_lab) < ШКІРА_ΔE]
        до = sum(m)
        if шк and до and len(шк) <= до / 2:
            for i in шк:
                m[i] = False
            чому.append("шкіру відрізано за твоїм кольором шкіри (%d %% плями)" % round(100 * len(шк) / до))
        elif шк:
            чому.append("шкіру НЕ відрізано: річ сама близька до кольору твоєї шкіри")
    m = _морфологія(_морфологія(m, w, h, True), w, h, False)        # відкриття
    m = _морфологія(_морфологія(m, w, h, False), w, h, True)        # закриття
    m = _найбільша_пляма(m, w, h)
    частка = sum(m) / float(w * h)
    return m, round(частка, 3), "; ".join(чому)


def поправка_тла(rgb, m, w, h, стеля=1.25):
    """(rgb, підсилення) — експозиція за білим тлом, як `жнива_колір.поправка_тла`.

    Тло, яке фотограф мав за біле (світле L ≥ 80 і безбарвне C < 8), — еталон білого в
    самому кадрі: канали множаться так, щоб воно стало білим, зі стелею 1.25. Кольорове
    чи темне тло поправки не дає (None)."""
    рамка = [i for i in _рамка_кадру(w, h) if not m[i]]
    if len(рамка) < 30:
        return rgb, None
    тло = [max(1.0, _медіана([rgb[i][к] for i in рамка])) for к in range(3)]
    L, C_, _h = cs.lch(cs.to_lab(tuple(int(x) for x in тло)))
    if L < 80 or C_ >= 8:
        return rgb, None
    п = [min(стеля, max(1.0, 250.0 / x)) for x in тло]
    return ([tuple(min(255, int(round(p[к] * п[к]))) for к in range(3)) for p in rgb],
            round(sum(п) / 3.0, 3))


def _k_середні(точки, к, сід=СІД, кроків=25):
    """k-means у Lab (k-means++ з сідом) → (центри, мітки). Чистий Python, без numpy."""
    г = _random.Random(сід)
    центри = [г.choice(точки)]
    while len(центри) < к:
        відст = [min(_math.dist(т, ц) ** 2 for ц in центри) for т in точки]
        сума = sum(відст)
        if сума <= 0:
            break
        поріг, нак = г.random() * сума, 0.0
        for т, в in zip(точки, відст):
            нак += в
            if нак >= поріг:
                центри.append(т)
                break
    мітки = [0] * len(точки)
    for _крок in range(кроків):
        мітки = [min(range(len(центри)), key=lambda j: _math.dist(т, центри[j])) for т in точки]
        нові = []
        for j in range(len(центри)):
            свої = [т for т, м in zip(точки, мітки) if м == j]
            нові.append(tuple(sum(т[к] for т in свої) / len(свої) for к in range(3)) if свої else центри[j])
        зсув = max(_math.dist(a, b) for a, b in zip(центри, нові))
        центри = нові
        if зсув < 1.0:
            break
    return центри, мітки


def _слово_кольору(lab):
    """(слово лексикону, у_вікні) — те саме правило «найтісніше вікно», що підписує палітру."""
    import palettes as _ПЛ
    сл, як = _ПЛ._назва(tuple(lab))
    return сл, (як == "у вікні")


def кластери(labs):
    """k-means над пікселями плями → [{слово, частка, lab, hex, у_вікні}], злиті за словом.

    Кластери з ОДНАКОВИМ словом зливаються (як у жнивах): розділяти «чорний» на дві тіні
    правилам не треба, а частку роздрібнення применшує. Кластер < 2 % — шум."""
    if len(labs) < 300:
        return []
    г = _random.Random(СІД)
    точки = labs if len(labs) <= ВИБІРКА else г.sample(labs, ВИБІРКА)
    центри, мітки = _k_середні(точки, min(К_КЛАСТЕРІВ, max(1, len(точки) // 100)))
    за_словом = {}
    for j, ц in enumerate(центри):
        частка = sum(1 for м in мітки if м == j) / float(len(мітки))
        if частка < 0.02:
            continue
        сл, у_вікні = _слово_кольору(ц)
        к = за_словом.setdefault(сл, dict(слово=сл, частка=0.0, lab=[0.0, 0.0, 0.0], у_вікні=у_вікні))
        сума = к["частка"] + частка
        к["lab"] = [(к["lab"][i] * к["частка"] + ц[i] * частка) / сума for i in range(3)]
        к["частка"] = сума
        к["у_вікні"] = к["у_вікні"] or у_вікні
    вих = []
    for к in за_словом.values():
        к["lab"] = [round(x, 2) for x in к["lab"]]
        к["частка"] = round(к["частка"], 3)
        к["hex"] = cs.hex_з_lab(tuple(к["lab"]))
        вих.append(к)
    return sorted(вих, key=lambda x: -x["частка"])


def _тінь(a, b, поріг=8.0, розрив_L=30.0):
    """Чи другий кластер — лише тінь першого (той самий прийом, що `жнива_колір._тінь`)."""
    if abs(a[0] - b[0]) >= розрив_L:
        return False
    return cs.de00((b[0], a[1], a[2]), tuple(b)) < поріг


def звести(кл, слово_моделі=None):
    """Кластери + слово моделі → (основний, другий, спір) — порядок рішень жнив v2.

    Основний — найбільший кластер У СІМ'Ї ТОНУ, яку назвала модель (на фото в руці чи на
    тілі найбільшим буває тінь або підкладка); коли в її сім'ї кластера нема — найбільший,
    і `спір` несе обидва слова (як рядок 135: вимір і слово названі, жодне мовчки не
    перемагає). Другий колір — кластер ≥ 20 % іншої сім'ї, що не є тінню основного."""
    if not кл:
        return None, None, None
    сім_м = V.сім_я_слова(слово_моделі) if слово_моделі else None
    у_сім_ї = [к for к in кл if сім_м and V.сім_я_слова(к["слово"]) == сім_м]
    основний = (у_сім_ї or кл)[0]
    спір = None
    if слово_моделі and not у_сім_ї:
        спір = dict(вимір=основний["слово"], модель=слово_моделі,
                    сім_я_виміру=V.сім_я_слова(основний["слово"]), сім_я_моделі=сім_м,
                    чому="сім'я тону виміру не збіглася зі словом стилістки — у вердикті колір виміру")
    другий = next((к for к in кл if к is not основний and к["частка"] >= 0.2
                   and V.сім_я_слова(к["слово"]) != V.сім_я_слова(основний["слово"])
                   and not _тінь(основний["lab"], к["lab"])), None)
    return основний, другий, спір


def виміряти(пікселі, слово_моделі=None, шкіра_hex=None, рамка=None):
    """Пікселі речі (кадр, вирізаний за рамкою моделі) → вимір кольору або причина, чому нема.

    Вихід: {lab, hex, слово, у_вікні, частка, маска, другий, спір, кластери, чому,
    рамка_виміру, поправка_тла}; без виміру — {lab: None, чому}. Колір ВИМІРЯНИЙ, а не
    hex моделі: слово моделі — лише свідок, і спір із ним називається полем `спір`."""
    w, h, rgb = розпакувати(пікселі)
    шкіра_lab = cs.hx(шкіра_hex) if шкіра_hex else None
    m, частка, чому = маска(rgb, w, h, шкіра_lab)
    рамка_виміру = "у рамці, яку назвала стилістка" if рамка else "увесь кадр (рамки не названо)"
    if частка < МІН_ЧАСТКА:
        return dict(lab=None, маска=частка, рамка_виміру=рамка_виміру,
                    чому="річ не відділилась від тла (%s; пляма %.1f %% кадру)" % (чому, частка * 100))
    rgb, поправка = поправка_тла(rgb, m, w, h)
    labs = [cs.to_lab(p) for p, так in zip(rgb, m) if так]
    кл = кластери(labs)
    основний, другий, спір = звести(кл, слово_моделі)
    if not основний:
        return dict(lab=None, маска=частка, рамка_виміру=рамка_виміру,
                    чому="замало пікселів речі для виміру (%d)" % len(labs))
    if поправка:
        чому += "; тло біле, експозиція ×%.2f" % поправка
    return dict(lab=list(основний["lab"]), hex=основний["hex"], слово=основний["слово"],
                у_вікні=основний["у_вікні"], частка=основний["частка"], маска=частка,
                другий=(dict(слово=другий["слово"], hex=другий["hex"], частка=другий["частка"])
                        if другий else None),
                спір=спір, кластери=кл, чому=чому, рамка_виміру=рамка_виміру,
                поправка_тла=поправка, пікселів=len(labs))


