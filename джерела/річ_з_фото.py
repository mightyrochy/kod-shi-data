def _дуга_членство(h, дуги):
    """Сила належності кута тону до найближчої з дуг: 1 усередині, далі — м'яке плече."""
    найкр = 0.0
    for д in дуги or ():
        a, b = float(д[0]), float(д[1])
        всередині = (a <= h <= b) if a <= b else (h >= a or h <= b)
        if всередині:
            return 1.0
        відст = min(min(abs(h - a), 360 - abs(h - a)), min(abs(h - b), 360 - abs(h - b)))
        найкр = max(найкр, min(1.0, 2.0 * cs.soft(відст, -1e9, 0.0, ШИРИНА_H)))
    return найкр


def членство_в_палітрі(lab, П):
    """K-PAL-17: {сила, роль, стан, частки, сім_я} кольору речі в практиковій палітрі жінки."""
    from колір_річ import нейтраль
    L, C_, h = cs.lch(tuple(lab))
    в = П["вікна"]
    чL = cs.soft(L, в["L"][0], в["L"][1], ШИРИНА_L)
    if нейтраль(tuple(lab)) is not None:
        сила, чC, чh = чL, None, None
        роль = "темна нейтраль" if L < 35 else ("світла нейтраль" if L > 80 else "нейтраль")
        сім = "нейтраль"
    else:
        чC = cs.soft(C_, в["C"][0], в["C"][1], ШИРИНА_C)
        дуги = [д for сім_, дд in в["сім_ї"].items() if сім_ != "очі" for д in дд]
        чh = _дуга_членство(h, дуги)
        очі = _дуга_членство(h, в["сім_ї"].get("очі") or [])
        if очі > чh:
            чh = очі
        сила = чL * чC * чh
        роль = "акцент (сім'я твоїх очей)" if очі >= 0.99 else "колір"
        import palettes as _ПЛ
        сім = (_ПЛ.сім_я_тону(h) or ("інша",))[0]
    стан = "у палітрі" if сила >= У_ПАЛІТРІ else ("на межі" if сила >= НА_МЕЖІ else "поза палітрою")
    return dict(сила=round(сила, 3), роль=роль, стан=стан, сім_я=сім,
                частки=dict(L=round(чL, 3), C=(round(чC, 3) if чC is not None else None),
                            тон=(round(чh, 3) if чh is not None else None)))


