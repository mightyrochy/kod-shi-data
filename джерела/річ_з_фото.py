ПРЕФІКС_ІД = "її-"        # ід речі з фото в пулі й образі: «її-ф1» (у каталозі таких нема)
_ДОВЖИНА_РІВЕНЬ = {"міді": "литка"}     # слово моделі → рівень `композитор_річ._РІВЕНЬ_ЗОНА`


def запис_каталогу(річ):
    """Річ з фото → запис того самого виду, що рядок каталогу: пул, суд і картка беруть її
    тим самим шляхом, що й речі крамниць. Колір — ВИМІРЯНИЙ (`вимір.lab`), слово — виміру
    або моделі; ціни й посилання нема (її річ не продається), `власна` каже це полем."""
    вим = річ.get("вимір") or {}
    lab = вим.get("lab")
    ід = ПРЕФІКС_ІД + str(річ.get("ід") or "ф?")
    з = dict(id=ід, слот=річ.get("слот"),
             назва=(річ.get("назва") or ("твоя річ з фото" if річ.get("фото") else "твоя річ")),
             власна=True, чия=(річ.get("чия") or "невідомо"), фото_ід=річ.get("фото"),
             закріплена=bool(річ.get("закріплена")))
    if lab:
        з.update(lab=tuple(lab), hex=(вим.get("hex") or cs.hex_з_lab(tuple(lab))),
                 колір=(вим.get("слово") or річ.get("колір")), джерело_кольору="фото жінки")
    elif річ.get("колір") in V.ЛЕКСИКОН and not річ.get("фото"):
        # РІЧ СЛОВАМИ (рядок 157): колір — ЇЇ СЛОВО, і в пул він іде так само, як слово
        # крамниці в каталозі: центр вікна + `колір_не_вимір`. Без цього правила образу, що
        # порівнюють кольори речей, її річ мовчки пропускали (lab нема — речі для них нема);
        # тепер вони судять на рівні вікон або кажуть «код не знає» з її річчю в переліку.
        from фід_збагачення import не_вимір_кольору as _нвк
        import palettes as _ПЛ
        вікно = V.ЛЕКСИКОН[річ["колір"]]
        з.update(lab=tuple(_ПЛ._центр(вікно)), колір=річ["колір"], джерело_кольору="її слово",
                 колір_не_вимір=_нвк(вікно, річ["колір"], "її слово", " (фото нема: так вона описала річ)"))
        з["hex"] = cs.hex_з_lab(з["lab"])
    elif річ.get("колір"):
        з.update(колір=річ["колір"], джерело_кольору="слово стилістки")
    if річ.get("колір"): з["колір_стилістки"] = річ["колір"]   # свідок поруч із виміром (рядок схеми)
    if річ.get("крій"): з["крій"] = річ["крій"]
    if річ.get("довжина"): з["довжина_рівень"] = _ДОВЖИНА_РІВЕНЬ.get(річ["довжина"], річ["довжина"])
    if річ.get("матеріал"): з.update(матеріал=річ["матеріал"], волокно=річ["матеріал"])
    if річ.get("принт"): з["візерунок"] = ("solid" if річ["принт"] == "однотонний" else річ["принт"])
    if річ.get("ошатність") is not None: з["формальність_фото"] = річ["ошатність"]
    return з


ОСНОВНІ_СЛОТИ = ("сукня", "комплект", "верхній_шар", "верх", "низ")   # річ, що несе площу образу


def основа_з_речі(речі, вибір, риси, source="uncontrolled", intent="conventional"):
    """Закріплена річ з фото стає ОСНОВОЮ образу, коли основи жінка не обирала сама.

    «Якір першим» (K-COMP-02) для її речі: `вибір_кольору.база_hex` → `якір_тон` дуг схеми і
    вікно сім'ї основи в пулі (`палітра_специфікація.специфікація`) — решта образу добирається
    навколо кольору її речі, а не навколо першої рекомендованої основи. Не стає, коли:
    · основу вона обрала на екрані палітри — її вибір сильніший (`None`);
    · річ мала (пояс, сумка) — схема тримається великих площ (`ОСНОВНІ_СЛОТИ`);
    · колір нейтральний (C* < `bases.АХРОМАТИЧНА_МЕЖА`) — надійного тону нема, те саме
      правило, що в `міст_основи._пакет`;
    · колір поза її палітрою (K-PAL-17) — будувати дуги на ньому означало б обсипати образ
      тим самим чужим кольором; схема лишається на її палітрі, а річ іде «без замків».
    `риси()` — лінива функція рис: рахується лише тоді, коли річ пройшла решту умов."""
    if (вибір or {}).get("база_hex"):
        return None
    import bases as _ОС
    for р in закріплені(речі):
        lab = (р.get("вимір") or {}).get("lab")
        if р.get("слот") not in ОСНОВНІ_СЛОТИ or not lab or cs.lch(tuple(lab))[1] < _ОС.АХРОМАТИЧНА_МЕЖА:
            continue
        F = риси() or {}
        if not (F.get("шкіра") and any(k.startswith("волосся") for k in F)):
            return None
        import palettes as _ПЛ
        if членство_в_палітрі(lab, _ПЛ.палітра_практична(F, source=source, intent=intent))["стан"] == "поза палітрою":
            return None
        з = запис_каталогу(р)
        return dict(вибір or {}, база=(з.get("колір") or "колір її речі"), база_hex=з["hex"],
                    база_тип="колір", база_з_речі=з["id"])
    return None


def власні(записи):
    """Записи каталогу, що є речами жінки з фото й стоять у кожному образі."""
    return [з for з in (записи or []) if isinstance(з, dict) and з.get("власна") and з.get("закріплена")
            and з.get("слот") and str(з.get("id") or "").startswith(ПРЕФІКС_ІД)]


def пул_із_закріпленими(кандидати, записи, тіло=None):
    """Пул, у якому слот закріпленої речі несе ЛИШЕ її, а слоти, що вона займає, порожні.

    Механіка «якір першим» (K-COMP-02, `composer._портфель` O2 — «найвиразніша річ пулу і
    найкраща комбінація навколо неї»), але якір тут обрала ЖІНКА, а не виразність: решта
    слотів лишається пулом каталогу, і модель збирає образ навколо її речі. Слот, який річ
    займає структурно (сукня — верх і низ), знімається з пулу, бо до сукні їх не додають
    (`пакет_моделі`: «до комплекту не додається ні верх, ні низ»). Так «іншої речі в її
    слоті» модель не має звідки взяти — тримає це пул, а не слухняність."""
    if not записи:
        return кандидати
    import composer as _КМ
    вих = dict(кандидати)
    for з in записи:
        сл = з["слот"]
        for інший in займає(сл) - {сл}:
            вих.pop(інший, None)
        рядок = _КМ._у_річ(dict(з), сл, тіло)
        рядок.setdefault("гілка", "ядро")
        вих[сл] = [рядок]
    return вих


def рядок_пакета(записи, номер):
    """Вимога ПАКЕТ_V1 словами: її річ у кожному образі, її слот не дублюється.

    `номер(id)` — «#N·MM», яким модель називає річ (нумерація пулу)."""
    р = []
    for з in записи:
        займ = sorted(займає(з["слот"]) - {з["слот"]})
        р.append("«%s» (%s) — РІЧ ЖІНКИ з її фото, %s: стоїть у КОЖНОМУ образі, не міняй її й не "
                 "клади іншої речі в слот «%s»%s. Решту образу збирай навколо неї — так, щоб вона "
                 "виглядала найкраще саме на цій жінці."
                 % (з.get("назва") or "її річ", номер(з["id"]),
                    "її власна" if з.get("чия") == "моя" else "вона думає її купити" if з.get("чия") == "хочу купити"
                    else "річ, про яку вона питає", з["слот"],
                    ("; до неї не додаються: %s" % ", ".join(займ)) if займ else ""))
        # БЕЗ ЗАМКІВ (п.5): код сказав «з умовою» чи «краще інша» — річ лишається, а решта
        # пом'якшує; вимога названа тим самим вердиктом, що жінка чула в розмові
        if з.get("пом_якшення"):
            р.append("Код каже, що «%s» їй %s; вона обрала її сама, тож річ лишається, а решта образу "
                     "пом'якшує: %s." % (з.get("назва") or "її річ",
                                         "личить з умовою" if з.get("вердикт_рівень") == "з умовою" else "личить гірше за інші",
                                         "; ".join(з["пом_якшення"])))
    return р


def закріпити_в_образі(ід, словник):
    """Склад образу → той самий склад, у якому КОЖНА закріплена річ жінки є, а в її слоті й
    у слотах, які вона займає, іншої речі нема. Повертає (ід, зміни).

    Це тримає КОД на кожному розборі відповіді моделі (`розбір_відповідей._запис_образу`),
    а не слухняність моделі: модель, яка забула річ або поклала другу сукню, дістає образ,
    у якому річ стоїть і сукня одна, — і зміни названі (`зміни`: додано / знято)."""
    закр = [(і, р) for і, р in (словник or {}).items()
            if isinstance(р, dict) and р.get("власна") and р.get("закріплена")
            and str(і).startswith(ПРЕФІКС_ІД) and р.get("слот")]
    # Порожній склад — не образ, а «з каталогу нічого не впізнано»: так приходять руки без
    # каталогу (3–4), чий текст розбирається далі як вигадані речі. Дописати сюди її річ
    # означало б видати одну річ за образ і закрити їм шлях розбору.
    if not закр or not ід:
        return list(ід), None
    зайняті = set()
    for _і, р in закр:
        зайняті |= займає(р["слот"])
    свої = {і for і, _р in закр}
    знято = [і for і in ід if і not in свої and (словник.get(і) or {}).get("слот") in зайняті]
    вих = [і for і in ід if і not in знято]
    додано = [і for і, _р in закр if і not in вих]
    вих = додано + вих
    return вих, ({"додано": додано, "знято": знято} if (додано or знято) else None)


НОТА_БЕЗ_ЗАМКІВ = ("річ жінки з фото — її явний вибір, і він сильніший за гейт коду (CLAUDE.md "
                   "п.9): образ з нею збирається, а решту код добирає так, щоб пом'якшити")


def без_замків(блокує, знахідки, речі):
    """Знахідки-гейти, що стосуються ЛИШЕ її речі з фото, стають репліками з нотою.

    Без замків (рядок 152, п.5 наряду): «Річ, що „не личить", можна зібрати все одно: явний
    вибір жінки сильніший за гейт коду». Гейт над її річчю в кожному образі відкидав би КОЖЕН
    образ, бо річ стоїть у всіх; тож він не блокує, а лишається знахідкою з тією самою силою
    й нотою `без_замків` — модель, суд і звіт бачать його, образ іде у вибір."""
    свої = {r.get("id") for r in (речі or []) if str(r.get("id") or "").startswith(ПРЕФІКС_ІД)}
    # гейт жорсткого «ні» (`pipeline`, знахідка «профіль») називає річ НАЗВОЮ, а не id —
    # тож її річ упізнається й за назвою (рядок 157: «світлі джинси кльош» під «ні» профілю
    # стенда відкидали кожен образ руки 1–2, бо річ стоїть у всіх)
    свої |= {r.get("назва") for r in (речі or []) if r.get("id") in свої and r.get("назва")}
    if not свої:
        return блокує, знахідки
    def _лише_її(з):
        """Чи знахідка — лише про її річ(і): порожнє `речі` — про образ, а не про неї."""
        рр = {str(x) for x in (з.get("речі") or [])} if isinstance(з, dict) else set()
        return bool(рр) and рр <= свої
    for з in знахідки or ():
        if _лише_її(з) and (з.get("регістр") == "гейт" or з.get("блокує")):
            з.update(регістр="репліка", блокує=False, без_замків=НОТА_БЕЗ_ЗАМКІВ)
    return [з for з in (блокує or []) if not _лише_її(з)], знахідки


# ── РУКИ 3–4: МОДЕЛЬ БЕЗ КОДУ Й КАТАЛОГУ (п.6 наряду) ─────────────────────────────
# Річ жінки в них теж є — у промпті, словами, і фото тим самим першим викликом, що й
# руки 1–2. Код її туди НЕ вписує: розбір лише впізнає рядок, який модель позначила
# міткою, — інакше контроль без коду перестав би бути без коду.
МІТКА_РУК_БЕЗ_КОДУ = "Твоя річ"
_МІТКА_РЕГ = __import__("re").compile(r"^\W*твоя\s+річ\b", __import__("re").I)


def рядок_рук_без_коду(речі):
    """Блок промпту рук 3–4: її закріплена річ словами — рід, колір (слово й hex виміру), крій,
    довжина, тканина, принт — і прохання позначити її рядок у відповіді. Без речі — ""."""
    р = []
    for x in закріплені(речі):
        вим = x.get("вимір") or {}
        колір = вим.get("слово") or x.get("колір")
        ознаки = [x.get("слот")]
        if колір:
            ознаки.append("колір %s%s" % (колір, (" %s" % вим["hex"]) if вим.get("hex") else ""))
        for к, п in (("крій", "крій"), ("довжина", "довжина"), ("матеріал", "тканина"), ("принт", "принт")):
            if x.get(к):
                ознаки.append("%s %s" % (п, x[к]))
        р.append("· %s — %s" % (x.get("назва") or "її річ", ", ".join(о for о in ознаки if о)))
    if not р:
        return ""
    # річ словами (рядок 157) фото не має — заголовок не каже «з фото», коли фото нема
    заголовок = ("ЇЇ РІЧ З ФОТО" if all(x.get("фото") for x in закріплені(речі))
                 else "ЇЇ РІЧ (з фото або описана її словами)")
    return ("%s — стоїть в образі: не міняй її й не клади іншої речі в її слот; решту "
            "образу вигадай навколо неї. Рядок цієї речі у відповіді почни словами «%s:».\n%s"
            % (заголовок, МІТКА_РУК_БЕЗ_КОДУ, "\n".join(р)))


def впізнати_в_тексті(речі, речі_паспорта):
    """Рука без коду (3–4): рядок, який модель позначила «Твоя річ:», — її річ з фото.

    Упізнаний рядок дістає той самий ід, що в руках 1–2 («її-ф1»), тож картка покаже її фото.
    Річ, якої модель не назвала, не дописується, чужі не знімаються. Повертає (речі, стан):
    `стан` = {названо, закріплено, чому} або None, коли закріпленої речі нема."""
    закр = [запис_каталогу(р) for р in закріплені(речі_паспорта)]
    if not закр:
        return речі, None
    вих, впізнано = [], []
    for r in (речі or []):
        if isinstance(r, dict) and _МІТКА_РЕГ.match(str(r.get("назва") or "")):
            вільні = [з for з in закр if з["id"] not in впізнано]
            з = next((з for з in вільні if з["слот"] == r.get("слот")), вільні[0] if вільні else None)
            if з:
                впізнано.append(з["id"])
                вих.append(dict(r, id=з["id"], назва=з.get("назва"), власна=True))
                continue
        вих.append(r)
    return вих, dict(названо=len(впізнано), закріплено=len(закр),
                     чому=(None if len(впізнано) == len(закр) else
                           "модель не позначила в образі річ з фото (%d із %d) — картка показує, що вона написала"
                           % (len(впізнано), len(закр))))


МАРКЕР_ФОТО = "її-фото:"  # «адреса» фото її речі в описі: показ підставляє байти з телефона


def картка(з):
    """Запис каталогу її речі → картка показу: без крамниці, ціни й посилання.

    Фото лежить на телефоні (репліка розмови), тож картка несе лише його ід (`фото_ід`);
    показ бере байти звідти сам. `власна` — позначка «твоя річ / річ з фото» і причина,
    чому «Разом» її не рахує."""
    return dict(id=з["id"], назва=з.get("назва"), слот=з.get("слот"), фото=None, урл=None, ціна=None,
                фото_усі=[], власна=True, чия=з.get("чия") or "невідомо", фото_ід=з.get("фото_ід"),
                закріплена=bool(з.get("закріплена")),
                **({"пом_якшення": з["пом_якшення_жінці"]} if з.get("пом_якшення_жінці") else {}))


def картки_з_паспорта(паспорт, судити=None):
    """{id: картка} для всіх речей з фото в паспорті (закріплених і ні).

    `судити(річ)` — вердикт коду над річчю (`суд_у_виклику` з рисами цього виклику); коли
    він є, закріплена річ, що «не личить», несе на картку м'який рядок `пом_якшення`."""
    вих = {}
    for р in ((паспорт or {}).get("речі_з_фото") or []):
        if isinstance(р, dict) and р.get("ід"):
            з = запис_каталогу(р)
            if судити is not None and р.get("закріплена"):
                з["пом_якшення_жінці"] = пом_якшення(судити(р))["жінці"]
            к = картка(з)
            вих[к["id"]] = к
    return вих
