def для_моделі(річ):
    """Річ з фото для «паспорта досі» в промпті: слова, без чисел виміру.

    Модель бачить колір СЛОВОМ ВИМІРУ, коли код уже поміряв (свідок сильніший за її
    перше слово), і вердикт коду реченням, яке вона переказує. Lab, hex і рамка до неї не
    їдуть: вона компонує й говорить словами, а числа — внутрішня шкала коду."""
    в = {k: річ.get(k) for k in ("ід", "фото", "назва", "слот", "колір", "матеріал", "крій",
                                 "довжина", "принт", "ошатність", "чия")
         if річ.get(k) not in (None, "", [])}
    if "ошатність" in в:
        в["ошатність"] = _БР.щабель_код(в["ошатність"]) or в["ошатність"]
    вим = річ.get("вимір") or {}
    if вим.get("слово"):
        в["колір"] = вим["слово"]
    ве = річ.get("вердикт") or {}
    # ВЕРДИКТ КОДУ — ВНУТРІШНЬОЮ МОВОЮ (Ч-1, 26.09.2026, п.12): доти тут їхало готове
    # речення українською. Тепер — рівень і заяви кодами, а поруч визначення ВЖИТИХ кодів
    # (`_словник_заяв`): словник заяв один на всю систему, і функціональна модель читає ті
    # самі означення, що й перекладачка.
    if ве.get("повідомлення"):
        в["вердикт_коду"] = dict(рівень=ве.get("рівень"), заяви=ве["повідомлення"]["statements"],
                                 означення=_словник_заяв(ве["повідомлення"]))
    if річ.get("закріплена") is not None:
        в["у_кожному_образі"] = bool(річ.get("закріплена"))
    return в


