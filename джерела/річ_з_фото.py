def речі_з_відповіді_фото(відповідь, фото, досі=None, власні=None):
    """Відповідь задачі «речі з фото» → {речі_з_фото, незнайомі, причина}.

    `власні` — ті самі `own_items`, що пішли в промпт (`промпт_фото`). «mine» моделі —
    свідок «річ її» (`чи_її`) лише тоді, коли модель бачила її речі словами: правило промпта
    «Only an item her words name is "mine"» без її слів виконати нема з чого. Без них «mine»
    читається «невідомо» (рядок 1882: живий С6 — у промпті лише фото, модель назвала «mine»
    сорочку, штани й туфлі кадру, і всі три стали в кожен образ «твоєю річчю»). Коли її речі
    словами несуть слот (`мовний_шар._її_речі`: «блуза» → верх), «mine» моделі тримається лише
    на речі, що стоїть на місці названої (`займають_одне`): модель, що бачила «моя блуза»,
    не робить її штанів і туфель з того самого кадру.

    Коди → слова словника (`ключ_поля`); код поза переліком — None і рядок у `незнайомі`, не
    здогад. Далі — той самий `речі_з_json`, що й для виклику 0: ід ставить код, злиття з
    паспортом досі поключове, нове фото без опису не губиться, закріплення — `закріпити`."""
    import протокол as _ПР
    об, причина, _ = _ПР.розбір_останній(відповідь, ("items",))
    сирі, незнайомі = [], []
    її = [в for в in (власні or []) if isinstance(в, dict)]
    if її:
        import мовний_шар as _МШ
        _речі = _МШ._її_речі(її)
        названі = {д["слот"] for д in _речі if д.get("стан") != "відмова"}
        лише_відмови = bool(_речі) and not названі
    for н, о in enumerate((об or {}).get("items") or [] if isinstance(об, dict) else []):
        if not isinstance(о, dict):
            незнайомі.append("items[%d]: не обʼєкт" % н)
            continue
        р = {"фото": о.get("photo"), "назва": о.get("name"), "ошатність": о.get("formality"),
             "чия": ключ_поля("owner", о.get("owner")) or "невідомо"}
        for поле, ключ in _ПОЛЯ_ФОТО:
            р[ключ] = ключ_поля(поле, о.get(поле))
            if р[ключ] is None and not __import__("внутрішня_мова").невідомо(о.get(поле)):
                незнайомі.append("items[%d].%s: код «%s» поза переліком" % (н, поле, о.get(поле)))
        if о.get("formality") is not None and _БР.число_щабля(о.get("formality")) is None \
                and not __import__("внутрішня_мова").невідомо(о.get("formality")):
            незнайомі.append("items[%d].formality: код «%s» поза переліком" % (н, о.get("formality")))
        if р["чия"] == "моя" and (not її or лише_відмови or (названі and not any(
                займають_одне(р["слот"], с) for с in названі))):
            р["чия"] = "невідомо"
        рамка = о.get("frame")
        if isinstance(рамка, dict):
            рамка = {"ліво": рамка.get("left"), "верх": рамка.get("top"),
                     "право": рамка.get("right"), "низ": рамка.get("bottom")}
        р["рамка"] = рамка
        сирі.append(р)
    return dict(речі_з_фото=речі_з_json(сирі, фото, досі), незнайомі=незнайомі,
                причина=(None if isinstance(об, dict) and isinstance(об.get("items"), list)
                         else (причина or "відповідь без списку «items»")))


# ═══════════ 3. ЗАКРІПЛЕННЯ: ЯКА РІЧ СТОЇТЬ У КОЖНОМУ ОБРАЗІ ═══════════════════════
# Слоти, що займають одне й те саме місце в структурі образу: сукня й комплект замінюють
# пару верх+низ (`outfit.елементи`, `pipeline._ТРЕТЯ`), тож дві закріплені речі з таких
# слотів в одному образі не стоять. Той самий слот — тим паче.
_ЗАЙМАЄ = {"сукня": {"сукня", "комплект", "верх", "низ"},
           "комплект": {"сукня", "комплект", "верх", "низ"},
           "верх": {"верх", "сукня", "комплект"},
           "низ": {"низ", "сукня", "комплект"}}


def займає(слот):
    """Слоти, які річ цього слота робить зайнятими в образі (сама — завжди)."""
    return set(_ЗАЙМАЄ.get(слот) or ()) | ({слот} if слот else set())


def займають_одне(а, б):
    """Чи дві речі цих слотів НЕ стоять разом в одному образі.

    ЩО БУЛО (знахідка менеджера 26.09, доповнення до наряду Л-5). `закріпити`
    рахувало конфлікт ПЕРЕТИНОМ `займає(а) & займає(б)`, а `займає` несе не лише
    місце речі, а й місця, які вона СОБОЮ закриває: верх закриває {верх, сукня,
    комплект}, низ — {низ, сукня, комплект}. Перетин цих двох непорожній
    ({сукня, комплект}) — і код читав її ВЕРХ і НИЗ з фото як дві речі на одному
    місці, лишаючи закріпленою лише пізнішу. Жінка клала два знімки, а руки
    збирали образ з однією її річчю.
    ЩО ТЕПЕР. Конфлікт — те, чим він і є: той самий слот, або слот однієї серед
    місць, які закриває інша. Верх і низ не конфліктують; сукня проти верху й
    проти низу — конфліктує, як і доти (сукня замінює пару). Та сама умова стоїть
    у Л-6 (`оцінка_образу.займають_одне`)."""
    if not а or not б:
        return False
    return а == б or а in займає(б) or б in займає(а)


