def вердикт(річ, F, T, сцен=None, source="uncontrolled", intent="conventional", типова_нагода=False):
    """«Чи підійде» — вердикт КОДУ над річчю з фото: знахідки, чекліст «без входу», рядок жінці.

    `річ` — запис паспорта `речі_з_фото` із `вимір` (або без нього: тоді колір — слово
    моделі як ЗОНА, і це названо). `F` — риси, `T` — тіло, `сцен` — нагода, злита з
    паспортом (`сценарій.з_показу`). Рівні: «личить» / «з умовою» / «краще інша»; жоден
    не забороняє зібрати образ із цією річчю (без замків, CLAUDE.md п.9)."""
    from реєстр_правил import _зн
    import palettes as _ПЛ, outfit as _O, колір_світлота as _КС, суд_погода as _ПОГ
    сцен = dict(сцен or {})
    слот = річ.get("слот")
    біля = біля_обличчя(слот) if слот else False
    знахідки, без_входу, пройдено, жінці, рівень = [], [], 0, [], "личить"
    # «решті» — що РЕШТА образу робить, щоб пом'якшити непройдену перевірку (п.5 наряду:
    # «код лише прибудовує решту так, щоб пом'якшити»); пари (моделі, жінці) — третя й
    # друга особа того самого; читає `пом_якшення`
    решті = []
    вим = річ.get("вимір") or {}
    lab = вим.get("lab")
    колір_чому = "виміряно з фото"
    if not lab and річ.get("колір") in V.ЛЕКСИКОН:
        # ЗОНА, НЕ ТОЧКА: центр вікна слова — останній свідок, і сила членства тоді
        # лише орієнтир (`фід_добір.частка_вікна` міряє те саме для речей каталогу)
        Llo, Lhi, Clo, Chi, д = V.ЛЕКСИКОН[річ["колір"]]
        lab = list(_ПЛ._центр((Llo, Lhi, Clo, Chi, д)))
        колір_чому = (("колір — словом стилістки («%s»), фото не дало виміру: %s" % (
            річ["колір"], вим.get("чому") or "пікселів нема")) if річ.get("фото") else
            ("колір — з її слів («%s»): фото нема, тож це зона слова, а не вимір" % річ["колір"]))
        без_входу.append("колір: " + колір_чому)
    # ── 1. K-PAL-17: палітра жінки ────────────────────────────────────────────
    if not lab:
        колір_чому = БЕЗ_КОЛЬОРУ
        без_входу.append("колір: нема ні виміру, ні слова кольору — палітра не судиться")
    elif not (F.get("шкіра") and any(k.startswith("волосся") for k in F)):
        без_входу.append("кольори профілю: без зчитаних кольорів палітра не рахується")
    else:
        П = _ПЛ.палітра_практична(F, source=source, intent=intent)
        ч = членство_в_палітрі(lab, П)
        зн, фраза = _зн_палітри(річ, ч, біля)
        знахідки.append(dict(зн, палітра=ч))
        if ч["стан"] == "у палітрі":
            пройдено += 1
        elif біля:
            рівень = "з умовою"
            жінці.append(фраза)
            решті.append(("біля обличчя — її нейтраль або колір її палітри: шарф, комір чи сережки",
                          "біля обличчя — твоя нейтраль або колір твоєї палітри: шарф, комір чи сережки"))
        else:
            жінці.append(фраза)
    # ── 2. K-CLR-02: контраст біля обличчя проти її власного ───────────────────
    річ_г = None
    if слот and lab:
        import composer as _КМ
        річ_г = _КМ._у_річ(запис_каталогу(dict(річ, вимір=dict(вим, lab=lab))), слот, T)
    if біля and річ_г is not None:
        особа = _O.контраст_особи(F, source)
        if not особа.get("доступно"):
            без_входу.append("контраст біля обличчя: %s" % (особа.get("чому") or "нема шкіри або волосся"))
        else:
            зк = _КС.біля_обличчя(_O.елементи([річ_г]), особа)
            if зк:
                знахідки += зк
                рівень = "з умовою"
                # напрям — із самої знахідки: «вище» лікує проміжна світлота між річчю й
                # обличчям, «нижче» — аксесуарний ремонт корпусу (блиск, світла деталь, помада)
                if "вище" in зк[0]["суть"]:
                    жінці.append("контраст речі з твоїм обличчям вищий за твій власний — між нею й "
                                 "обличчям дай щось проміжної світлоти (шарф чи комір)")
                    решті.append(("між нею й обличчям — річ проміжної світлоти (шарф чи комір)",) * 2)
                else:
                    жінці.append("біля обличчя річ тихіша за твій власний контраст — оживи обличчя "
                                 "деталлю: прикраса з блиском, світла деталь чи помада")
                    решті.append(("біля обличчя — прикраса з блиском або світла деталь, що повертає її власний контраст",
                                  "біля обличчя — прикраса з блиском або світла деталь"))
            else:
                пройдено += 1
    # ── 3. K-BOD-02: крій проти фігури — лише там, де річ сама дає контур ──────
    if слот in ("сукня", "комплект", "верхній_шар") and річ_г is not None:
        if not річ.get("крій"):
            без_входу.append("крій: стилістка його не назвала — проти фігури не судиться")
        elif not (T or {}).get("профіль"):
            без_входу.append("фігура: без обхватів крій не судиться")
        else:
            import silhouette as _СИЛ, силует_суд as _СС
            зс = _СС.відповідність(T, _СИЛ.обгортка(T, [річ_г]), intent)
            if зс:
                знахідки += зс
                рівень = "з умовою"
                _р = (зс[0].get("ремонт") or ["інша річ образу врівноважить"])
                _р = [_р] if isinstance(_р, str) else list(_р)
                жінці.append("крій веде контур не туди, куди твоя фігура просить: %s" % _р[0])
                решті.append(("контур урівноважити рештою: %s" % _р[0],) * 2)
            else:
                пройдено += 1
    elif слот in ("верх", "низ"):
        без_входу.append("крій проти фігури: верх чи низ сам контуру не дає — судиться в образі з другою половиною")
    # ── 4. K-KOH-05: ошатність речі проти нагоди ──────────────────────────────
    лоу, хай, звідки = _шкала_нагоди(сцен)
    ош = річ.get("ошатність")
    if ош is None:
        без_входу.append("ошатність речі: стилістка її не назвала")
    else:
        промах = (лоу - ОШАТНІСТЬ_ДОПУСК - ош) if ош < лоу - ОШАТНІСТЬ_ДОПУСК else \
                 ((ош - хай - ОШАТНІСТЬ_ДОПУСК) if ош > хай + ОШАТНІСТЬ_ДОПУСК else 0)
        if промах > 0:
            нижче = ош < лоу
            знахідки.append(_зн("K-KOH-05", "soft",
                "«%s»: річ %s за нагоду" % (_назва(річ), "буденніша" if нижче else "ошатніша"),
                [річ.get("ід") or "річ"],
                "ошатність речі %s проти смуги %.0f–%.0f (%s), допуск %d" % (ош, лоу, хай, звідки, ОШАТНІСТЬ_ДОПУСК),
                ремонт=["%s рівень рештою образу" % ("підняти" if нижче else "приглушити")],
                вимір=промах, поріг=0, повна=3.0))
            рівень = "краще інша" if промах >= 2 else ("з умовою" if рівень == "личить" else рівень)
            жінці.append("для цієї нагоди річ %s — %s рештою образу" % (
                "буденна" if нижче else "занадто ошатна", "підніми рівень" if нижче else "приглуш рівень"))
            решті.append(("%s рівень ошатності рештою образу" % ("підняти" if нижче else "приглушити"),) * 2)
        else:
            пройдено += 1
    if типова_нагода:
        без_входу.append("нагода: не названа — річ оцінено на звичайний день")
    # ── 5. K-WEA-01: погода для верхнього шару й тканини ──────────────────────
    мат = (річ.get("матеріал") or "").lower()
    опади = __import__("сценарій").канон_опади(сцен.get("опади"))
    if мат and any(v in мат for v in _ПОГ.ВОЛОГІ_ВЕТО):
        if опади in __import__("сценарій").МОКРІ_ОПАДИ:
            знахідки.append(_зн("K-WEA-01", "hard", "«%s»: %s у дощ псується" % (_назва(річ), мат),
                                [річ.get("ід") or "річ"], "вето корпусу: мокра погода й %s" % мат,
                                ремонт=["на дощовий день — інша річ; ця — в суху погоду"]))
            рівень = "краще інша"
            жінці.append("у дощ %s псується — на сьогодні краще інша" % мат)
            решті.append(("верхній шар, що накриває її річ від дощу, і взуття на мокру дорогу",
                          "верхній шар, що накриває її від дощу, і взуття на мокру дорогу"))
        elif опади is None:
            без_входу.append("опади: не названі, а %s боїться вологи" % мат)
        else:
            пройдено += 1
    if слот == "верхній_шар":
        т = сцен.get("темп_c")
        if т in (None, ""):
            без_входу.append("температура: не названа — верхній шар проти погоди не судиться")
        elif float(т) >= 18:
            знахідки.append(_зн("K-WEA-01", "hint", "«%s»: за %+.0f °C верхній шар зайвий — хіба що накинути"
                                % (_назва(річ), float(т)), [річ.get("ід") or "річ"],
                                "температурна мапа корпусу: від 18 °C — один шар (`outfit.ТЕМП_МАПА`)",
                                ремонт=["носити в прохолодніший день або накинути на плечі"]))
            жінці.append("за такої температури верхній шар зайвий")
        else:
            пройдено += 1
    if not слот:
        без_входу.append("слот: стилістка не назвала, яка це річ")
    рядок = _рядок_жінці(рівень, жінці, типова_нагода)
    if not річ.get("фото"):
        # РІЧ СЛОВАМИ (рядок 157): що колір не з фото — у рядку жінці, а не лише в чеклісті
        if lab:
            рядок += " Колір узято з твого опису («%s»), не з фото." % річ["колір"]
        else:
            рядок = (("Чи личить, сказати поки не можу" if рівень == "личить" else рядок.rstrip("."))
                     + ": колору цієї речі я не знаю — фото нема, і колір не названо, тож із твоєю "
                     "палітрою я її не звіряла. Назви колір словом — звірю.")
    return dict(рівень=рівень, рядок=рядок, знахідки=знахідки, колір=колір_чому, решті=решті,
                # «провал» — перевірка, яку річ не пройшла (колір поза палітрою далеко від
                # обличчя — теж: це правда про колір, хоч і не вада образу)
                чекліст=dict(пройдено=пройдено,
                             провал=[з["суть"] for з in знахідки
                                     if (з.get("палітра") or {}).get("стан") != "у палітрі"],
                             без_входу=без_входу))


