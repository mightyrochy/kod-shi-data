# ЩО БУЛО. Живий прогін 26.09 (`аудит/тести/2026-09-26_н1_живий_прогін.md`, пункт (а),
# сира відповідь `сирі_2026-09-26/…/seed3_02_речі_з_фото_шар_.txt`): жінка надіслала два
# фото — своєї спідниці й своїх козаків — зі словами «Збери образ під цю спідницю і чоботи
# для походу на концерт». Спідницю вона сфотографувала НА МОДЕЛІ, і модель із зором чесно
# назвала все, що в кадрі: `beige long-sleeved top` (owner «unknown»), `black pencil skirt`
# (owner «mine»), `silver heels` (owner «unknown»), `brown leather boots` (owner «mine»).
# `закріпити` не читало ні її слів, ні `чия`: закріплювалась КОЖНА річ зі слотом, поки не
# конфліктувала з пізнішою. Закріплених вийшло ТРИ замість двох, і на чужий бежевий топ код
# казав жінці «Цю річ ти обрала сама, тож вона в кожному образі» (`пом_якшення`), ставив
# його в кожен образ усіх чотирьох рук і віз у приміряння.
# ЩО ТЕПЕР. Річ у кожному образі — найінвазивніше, що код робить із її словом (той самий
# довід, що в рядку 157), тож потрібен СВІДОК, що річ її. Свідків три, від найсильнішого:
#   1. ЇЇ СЛОВО — слот цієї речі стоїть серед речей, які вона назвала сама (`названі`). У
#      шарі це `own_items`, чию цитату сторож М-1 знайшов у її словах дослівно
#      (`мовний_шар.цитата_тримає` → `_її_речі` → `паспорт_нагоди.паспорт_з_json(словами=…)`);
#      без шару цього свідка нема (Ч-4: код її слів не читає). Її слово переважає
#      «невідомо» моделі: така річ ще й стає «моя» (`речі_з_json`), як і доти для речі словами.
#   2. ОДНА РІЧ У КАДРІ — на цьому фото інших речей зі слотом нема, тобто це фото самої
#      речі («чи підійде мені ця річ і з чим її носити», рядок 152), і «інших речей у
#      кадрі», які можна переплутати з її, просто не існує.
#   3. `чия` МОДЕЛІ — не «невідомо»: модель, яка бачила її речі словами
#      (`her_items_in_words` промпта П-1), сказала, чия ця річ.
# Жодного свідка — річ лишається в паспорті з виміром і вердиктом (жінка бачить, що код на
# фото побачив), але не в кожному образі, і причина НАЗВАНА (`чому_не_закріплена`), не
# змовчана (CLAUDE.md п.4). Замка тут нема (п.9): щоб річ стала її, досить одного її слова
# про неї — наступний хід розмови її закріпить.
def чи_її(річ, речі, названі=None):
    """Чи є свідок, що річ із фото — її: її слово, одна річ у кадрі або `чия` моделі.

    `названі` — слоти речей, які вона назвала сама (`речі_з_json(словами=…)`)."""
    if not річ.get("фото"):
        return True            # річ словами (рядок 157) інакше в паспорт і не потрапляє
    if річ.get("слот") and річ.get("слот") in (названі or ()):
        return True
    у_кадрі = sum(1 for р in (речі or []) if isinstance(р, dict)
                  and р.get("фото") == річ.get("фото") and р.get("слот"))
    return у_кадрі <= 1 or річ.get("чия") not in (None, "", "невідомо")


def закріпити(речі, названі=None):
    """Позначити, які речі стоять у КОЖНОМУ образі руки 1: `закріплена` True/False.

    Закріплюється річ зі слотом, про яку є свідок, що вона ЇЇ (`чи_її`: її слово, одна річ
    у кадрі або `чия` моделі), поки вона не конфліктує з ПІЗНІШОЮ (свіжіша репліка —
    свіжіше питання). Конфлікт — той самий слот або структурне місце
    (`займають_одне`: сукня проти верху; верх і низ — НЕ конфлікт). Річ, що програла, лишається в паспорті з причиною
    `чому_не_закріплена`: вердикт «чи підійде» вона дістає так само. Явне «не збирати з
    нею» — рука жінки (`закріплена: False` із показу) — переважає і не перебивається.
    Річ без слота не закріплюється: у пулі їй нема місця, і це сказано причиною.

    ПРИЧИНА — КОД ЗАЯВИ, НЕ ФРАЗА (Ч-1, CLAUDE.md п.12; доповнення менеджера до Р-1):
    `чому_не_закріплена` несе сам код зі `внутрішня_мова.ЗАЯВИ`, як `фід_фото.чому_без_кадру`,
    а речення для жінки складає мовна модель. Ч-1 (#370) сюди не дійшов — три причини лежали
    українськими фразами; тепер кодами всі чотири, щоб поле не читалось двома типами."""
    зайняті = set()
    for р in reversed(речі):
        if р.get("рука") == "не закріплювати":
            р["закріплена"], р["чому_не_закріплена"] = False, "her_item_not_in_looks_she_said_no"
            continue
        сл = р.get("слот")
        if not сл:
            р["закріплена"], р["чому_не_закріплена"] = False, "her_item_slot_unclear"
            continue
        # СВІДОК «РІЧ ЇЇ» — ДО КОНФЛІКТУ (Р-1, див. `чи_її`): чужа річ у кадрі не лише не
        # закріплюється, а й не займає місця в образі — інакше срібні човники з фото її
        # спідниці й далі забирали б взуття в її ж козаків.
        if not чи_її(р, речі, названі):
            р["закріплена"] = False
            р["чому_не_закріплена"] = "her_item_not_named_others_in_frame"
            continue
        # КОНФЛІКТ — ЗА `займають_одне`, А НЕ ПЕРЕТИНОМ `займає` (знахідка 26.09,
        # див. докстрінг `займають_одне`): перетин робив її верх і низ з фото
        # двома речами на одному місці.
        if any(займають_одне(сл, б) for б in зайняті):
            р["закріплена"] = False
            р["чому_не_закріплена"] = "her_item_later_item_in_same_place"
            continue
        р["закріплена"] = True
        р.pop("чому_не_закріплена", None)
        зайняті.add(сл)
    return речі


def закріплені(речі):
    """Речі з фото, що стоять у кожному образі (порядок — як у паспорті)."""
    return [р for р in (речі or []) if isinstance(р, dict) and р.get("закріплена") and р.get("слот")]


