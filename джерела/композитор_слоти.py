def _влучає(r, q):
    """частка вікна (річ-зона) або точкове влучання; None — річ без кольору."""
    if not r.get("lab"): return None
    try:
        if r.get("вікно"):
            return feed.частка_вікна(r["вікно"], q)
        return 1.0 if feed.підходить(r["lab"], q) else 0.0
    except Exception as _e:
        import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
        if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
        return None


def _кандидати_гілки(речі, вікна, слот, ядро_ід, гілка, K, сід=0):
    """K речей слота, що влучають у ці вікна, але не в ядро; тег гілки і схема.

    Нічия розв'язується сідом, не порядком каталогу — та сама правка, що в
    `_кандидати_на_слот`; тут вона тримає гілку «на межі» в тому ж режимі, інакше
    сміливий намір лишився б детермінованим при випадковому ядрі."""
    у_слоті = [r for r in речі if r.get("слот") == слот]
    # ДВІ ХВИЛІ (Н-palette-2-098): запасне вікно (`спроба==1`, якірна нейтраль і
    # принт-ехо) не додає кандидатів, поки є хоч один із основного. Те саме
    # правило, що в `feed.покриття`, і той самий поділ — `feed.хвилі`.
    def _збір(вік):
        """(відстань, річ, вікно) для кожної речі слота, що влучає в одне з вікон `вік`."""
        out = []
        for q in вік:
            if q.get("слот") and q["слот"] != слот: continue
            for r in у_слоті:
                ч = _влучає(r, q)
                if not ч: continue
                d = (1.0 - ч) * 100.0 if r.get("вікно") else feed.відстань_до_центру(r["lab"], q)
                out.append((d, r, q))
        return out
    _осн, _зап = feed.хвилі(вікна)
    підходящі = _збір(_осн) or _збір(_зап)
    _перемішати(підходящі, сід, слот + "|межа")
    підходящі.sort(key=lambda x: x[0])
    вийшло, бачені = [], set(ядро_ід)
    for d, r, q in підходящі:
        к = r.get("group_id") or r.get("id")
        if к in бачені: continue
        бачені.add(к)
        вийшло.append(dict(r, _відстань=d, _вікно=q, _гілка=гілка, _схема=q.get("_схема")))
        if len(вийшло) >= K: break
    return вийшло


def _поза_палітрою(речі, вікна_усі, слот, зайняті, сід=0):
    """Речі слота з кольором, що не влучають у ЖОДНЕ вікно, — найдальші від палітри перші.

    Нічия — сідом (див. `_кандидати_на_слот`): «найдальші перші» теж дає плато
    рівних відстаней, і перший у фіді ставав єдиним дозволеним розривом."""
    у_слоті = [r for r in речі if r.get("слот") == слот and r.get("lab")]
    центри = [q for q in вікна_усі if not q.get("слот") or q["слот"] == слот]
    out, бачені = [], set(зайняті)
    for r in у_слоті:
        к = r.get("group_id") or r.get("id")
        if к in бачені: continue
        if any((_влучає(r, q) or 0) > 0 for q in центри): continue
        try:
            d = min(feed.відстань_до_центру(r["lab"], q) for q in центри) if центри else 0.0
        except Exception as _e:
            import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
            if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
            continue
        бачені.add(к)
        out.append(dict(r, _відстань=d, _вікно=None, _гілка=ГІЛКА_РОЗРИВ))
    _перемішати(out, сід, слот + "|розрив")
    out.sort(key=lambda r: -(r["_відстань"] or 0))
    return out


def _своя_мова(r, реєстр_людини):
    """Чи належить річ хоч одному з реєстрів, які назвала людина (K-REG-02).

    М'ЯКА ПЕРЕВАГА, А НЕ ВОРОТА, І НЕ ЗМІНА КОЛІРНОЇ ОСІ. Правило прямо
    забороняє робити з реєстру людини фільтр («не `hard`: людина, що назвала
    „класика“, має право на одну цитату з іншого реєстру»), тому річ чужого
    реєстру звідси НЕ зникає. Але й посунути її нижче за колірним балом не
    можна: docstring `_кандидати_на_слот` обіцяє, що порядок МІЖ різними `d` не
    змінюється ні на йоту. Лишається рівно одне місце, де перевагу видно й де
    вона нічого не коштує, — НІЧИЯ. Сьогодні її розв'язує сід, тобто монета;
    реєстр людини — краща підстава за монету й гірша за колір, і саме там він
    і стоїть."""
    if not реєстр_людини:
        return False
    try:
        import реєстри as _РЕ
        return bool(set(_РЕ.реєстр_речі(r).get("бали") or {}) & set(реєстр_людини))
    except Exception as _e:
        import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
        if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
        return False


def _кандидати_на_слот(речі, вікна, слот, тіло, сід=0, реєстр_людини=None):
    """K кандидатів, упорядкованих за відстанню до ЦЕНТРУ вікна.

    Центр, а не «всередині вікна»: усередині вікна всі рівні, і без осі впорядкування
    вибір знову впав би на порядок каталогу (те саме, від чого лікує R-PSY-03).

    ── НІЧИЮ РОЗВ'ЯЗУВАВ ПОРЯДОК КАТАЛОГУ (30.08.2026) ───────────────────────────
    ЩО ЦЕ МІНЯЄ В РІШЕННІ (правило 3, before/after, виміряно `вимір_лійки.py` на
    каталог_повний, сценарій «клуб, коктейльний, 22:00»):
      before — у слоті «взуття» 460 речей, 448 влучають у вікна, 410 різних моделей,
               до моделі доходять 5. Три різні сіди давали ТІ САМІ п'ять. Причина не
               в стелі: `d` для речей, чий колір узято ЗІ СЛОВА, ТОТОЖНЕ в межах
               одного слова (та сама частка того самого вікна), а `list.sort`
               стабільний — отже серед ~30 «чорних» перемагала перша В ПОРЯДКУ
               КАТАЛОГУ. Рядки вище обіцяють лікування від R-PSY-03; нічия вертала
               саме те, від чого вони лікують.
      after  — перед сортом пул перемішується сідом прогону. Сорт стабільний, тож
               порядок МІЖ різними `d` не змінюється ні на йоту: рухається лише те,
               що система вважає РІВНИМ. Різні прогони показують різних «чорних».

    СІД 0 = «СІДА НЕМА». Тоді нічию знову розв'язує фід — навмисно, щоб тести й CLI
    лишались порівнюваними з тим, що було до цієї правки. Стенд шле свій сід завжди,
    тож у режим відтворюваності не потрапляє жоден прогін перед людиною.

    ⚠ СИЛА ≤ ВЕРИФІКАЦІЯ (правило 4). Це НЕ покращення якості добору й не претендує
    на нього: жодних доказів, що випадковий представник класу кращий за перший у
    фіді, нема. Доведено лише, що клас рівних існує (вимір вище) і що вибір у ньому
    досі робив фід. Прибрано необоронну сталість, не додано якості.
    """
    у_слоті = [r for r in речі if r.get("слот") == слот]
    # ── ДВОСЛОТОВІ: РІЧ, ЯКА МОЖЕ СТАТИ В ЦЕЙ СЛОТ РІШЕННЯМ КОМПОЗИТОРА ────────
    # ЩО ЦЕ МІНЯЄ (правило 3, виміряно на ager 26.08.2026): `feed.слоти` рахувала
    # `слоти_альт` і не віддавала НІКОМУ — 12 кардиганів фіду назавжди лишались
    # «верхом». Отже гілка теми-11 «кардиган-як-верхній-шар» була недосяжна не
    # через дані, а через те, що поле нікуди не доїжджало: 0 кандидатів у
    # «верхній_шар» на фіді, де їх дванадцять.
    # ЧОМУ ЦЕ ЗАКОННО: `feed.слоти` прямо каже, що вибір слота для таких речей —
    # робота композитора («тут лише перестає губитись сам факт двозначності»).
    # Композитор і робить його ТУТ, і позначає річ, щоб це було видно у виході.
    альтернативні = [dict(r, слот=слот, _слот_альтернативний=True,
                          _слот_первинний=r.get("слот"))
                     for r in речі
                     if r.get("слот") != слот and слот in (r.get("слоти_альт") or ())]
    у_слоті = у_слоті + альтернативні
    if not у_слоті: return [], "у слоті нема речей після абсолютних фільтрів"
    # ДВІ ХВИЛІ (Н-palette-2-098) — те саме правило й у ЖИВІЙ дорозі добору, не
    # лише в гілках: запасне вікно (`спроба==1`) береться, лише коли основне не
    # дало нікого. Інакше найширший рядок слота вирішував би, що таке
    # «підходить», і колірний шар на «взуття»/«сумці» лишався б порожнім
    # твердженням — рівно те, що наряд і міряє.
    def _збір_слота(вік):
        """(відстань, річ, вікно) для речей слота у вікнах `вік`: зона слова через
        `описує_річ`/`частка_вікна`, точка з фото через `підходить`/`відстань_до_центру`."""
        out = []
        for q in (вік or []):
            if q.get("слот") and q["слот"] != слот: continue
            for r in у_слоті:
                if not r.get("lab"): continue
                try:
                    if r.get("вікно"):
                        # колір відомий словом — зона, не точка (feed.частка_вікна, 24.08.2026):
                        # кандидат при частці > 0; відстань — обернена частка, щоб більша
                        # частка ранжувалась вище, а точкові з фото лишались попереду
                        # РІД РЯДКА ПРОТИ РОДУ РЕЧІ (K-PAL-01, 17.09.2026): частка > 0 —
                        # це «хоч один вузол вікна назви пройшов», і нейтральним рядком
                        # у пул їхала хроматична річ своїм блідим краєм, а в пакет —
                        # своїм представником. `feed.описує_річ` вимагає, щоб рядок
                        # говорив про ТОЙ САМИЙ колір, яким річ поїде до моделі.
                        if not feed.описує_річ(r["lab"], q): continue
                        ч = feed.частка_вікна(r["вікно"], q)
                        if ч <= 0.0: continue
                        d = (1.0 - ч) * 100.0
                        r["_частка_вікна"] = ч
                    else:
                        if not feed.підходить(r["lab"], q): continue
                        d = feed.відстань_до_центру(r["lab"], q)
                except Exception as _e:
                    import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
                    if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
                    continue
                out.append((d, r, q))
        return out
    _осн_сл, _зап_сл = feed.хвилі(вікна or [])
    підходящі = _збір_слота(_осн_сл)
    # ГАРАНТІЯ СЛОТА (16.09.2026): коли дуга схеми дає в слоті менше за МІН_У_ДУЗІ
    # кандидатів (стенд: «низ» під тональною — 1 річ), запасна хвиля (нейтралі й
    # ширша дуга, `спроба=1`) ДОПОВНЮЄ основну, а не заміняє її. Доти запасна
    # бралась лише при порожній основній, і слот з однією річчю йшов до моделі як
    # «повний». Доповнені речі позначаються `_доповнено`; пакет пише їм `у_дузі: false`.
    if len({r.get("group_id") or r.get("id") for _d, r, _q in підходящі}) < МІН_У_ДУЗІ:
        _є_ід = {r.get("id") for _d, r, _q in підходящі}
        for _d, r, _q in _збір_слота(_зап_сл):
            if r.get("id") in _є_ід: continue
            r["_доповнено"] = True
            підходящі.append((_d + 100.0, r, _q))      # +100: доповнені завжди після основних
            _є_ід.add(r.get("id"))
    # НІЧИЯ ДІСТАЄТЬСЯ СІДУ, А НЕ ФІДУ. Сорт нижче стабільний, тому це рухає лише
    # рівні `d` (див. докстрінг). Речі з точковим кольором з фото мають неперервні
    # `d` і майже не мають нічиїх — там перемішування не міняє нічого, і це
    # правильно: воно адресне.
    _перемішати(підходящі, сід, слот)
    if not підходящі:
        # Вікна порожні — беремо все, що є, і КАЖЕМО про це. Мовчазний фолбек на
        # «будь-що з каталогу» був би тим самим, що ігнорувати вікна.
        # ⚠ ДЕДУПЛІКАЦІЯ ПО МОДЕЛІ ПОТРІБНА Й ТУТ. Перша версія цієї гілки брала
        # `у_слоті[:K]` без згортання, і на прогоні вийшло видно: «наступні за
        # порядком» показували ТУ САМУ модель тричі, у розмірах S/M/L. Тобто
        # альтернатива, яку система пропонує людині, була не альтернативою, а
        # тим самим взуттям. Це той самий модальний колапс, від якого лікує
        # group_id у `feed.покриття`, — і в фолбек-гілці він відтворювався заново.
        унік, бач = [], set()
        # той самий дефект, що й нижче: без осі впорядкування тут узагалі нема
        # ЧОГО втрачати від перемішування — порядок фіду не несе змісту
        _перемішати(у_слоті, сід, слот + "|фолбек")
        for r in у_слоті:
            к = r.get("group_id") or r.get("id")
            if к in бач: continue
            бач.add(к); унік.append(dict(r, _відстань=None, _вікно=None, _гілка=ГІЛКА_ЯДРО))
            if len(унік) >= K_НА_СЛОТ: break
        return (унік,
                "жодна річ слота не влучила у вікна — узято %d РІЗНИХ моделей без "
                "колірного критерію; вибір у цьому слоті НЕ спирається на палітру"
                % len(унік))
    # Ключ сорту двочленний: колірна відстань перша й незмінна, реєстр людини —
    # лише другим членом, тобто рухає РІВНЕ (див. `_своя_мова`).
    _свої = set(реєстр_людини or ())
    # ── K-PAL-02 / R-COL-17: СІМ'Я ОЧЕЙ ПЕРША СЕРЕД РІВНИХ ────────────────────
    # `palettes.рядки_у_фід` і `personal_palette.рядки_у_фід` ставлять кожному
    # рядку `ранг_риси` (очі 1, решта 2, макіяж останній) — це і є «перегук рис:
    # повторити колір очей як акцент» (K-PAL-02, перший за порядком за Perrett
    # 2023). Доти ранг лише СОРТУВАВ САМІ РЯДКИ в `запит_у_фід`, а добір читав
    # їх множиною — тобто порядок рядків не міняв нічого: кандидати сортуються
    # за колірною відстанню, і рядок, яким річ увійшла, у ключ не входив.
    # ЧОМУ ДРУГИМ ЧЛЕНОМ, А НЕ ПЕРШИМ. Колірна відстань лишається незмінною й
    # першою — те саме рішення, що зроблено для реєстру людини рядком нижче:
    # ранг рухає РІВНЕ, а не переставляє ближче за дальнє. Рівних тут багато за
    # побудовою: коли колір відомий словом, `d = (1 − частка) × 100` квантована
    # шириною вікна лексикону, і цілі класи речей мають однакове `d`.
    # ЧОМУ ПЕРЕД РЕЄСТРОМ. Реєстр — мова образу (T3, конвенція); «одяг обирають
    # до очей» — вимір на 200 учасниках (Perrett 2023, T2). Сильніший доказ іде
    # раніше в ключі.
    # ── R-COL-16: БІК b* РЕЧІ ПРОТИ ОЧЕЙ — ТРЕТІЙ ЧЛЕН, РУХАЄ ЛИШЕ РІВНЕ ──────
    # Рядок несе `b_бік` (+1 теплий / −1 холодний бік жовто-синьої осі), який
    # `palette.бік_b_проти_людини` прочитала з b* райдужки (Perrett 2023: вибір
    # одягу йде за очима; 2021: вісь вибору — b* речі). Річ на ПРОТИЛЕЖНОМУ боці
    # йде після рівних за відстанню й рангом риси — не викидається й не штрафується
    # числом: сила правила hint («a rule that admits 85 % of the space is not a
    # rule» — тому міряно пробою `проби/col_R-COL-16.py`, а не заявлено). Межі боку
    # ті самі, що в нейтралі (`реєстр_правил.C["b_нейтралі"]`), через
    # `palette.бік_b_речі`. Після рангу риси, бо те — порядок рядків тієї самої
    # лабораторії (R-COL-17, T2), і перед реєстром людини (T3 конвенція).
    def _проти_боку_b(r, q):
        """1, коли річ на протилежному боці b* від рядка (R-COL-16); інакше 0."""
        бік = int((q or {}).get("b_бік") or 0)
        if not бік or not r.get("lab"): return 0
        try: return 1 if _P_бік.бік_b_речі(r["lab"]) == -бік else 0
        except Exception as _e:
            import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
            if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
            return 0
    import palette as _P_бік
    підходящі.sort(key=lambda x: (x[0], int((x[2] or {}).get("ранг_риси") or 9),
                                  _проти_боку_b(x[1], x[2]),
                                  0 if _своя_мова(x[1], _свої) else 1))
    # ── ПУЛ РОЗТЯГУЄТЬСЯ ПО СЛОВАХ КОЛЬОРУ (27.08.2026, каталог_повний) ──────────
    # ВИМІРЯНО (measure_theme4, тепла-світла, верх+низ): п'ятірка верхів = п'ять
    # «світло-сірих» речей, бо колір зі слова — ЦЕНТР ОДНОГО ВІКНА, і всі п'ять мають
    # тотожну частку вікна; нічию розв'язував порядок каталогу (те, від чого лікує
    # R-PSY-03). Далі 25 комбінацій мали розкид координації 0 d_ok — K-COMP-01 і
    # K-COL-06 законно УТРИМУВАЛИСЬ, а тестувальниця бачила «альтернативи» з тієї
    # самої сірої футболки в п'яти артикулах. Тепер серед речей, чий колір узято
    # ЗІ СЛОВА, кожне слово (з модифікатором) дає один кандидат, і лише коли слів
    # менше за K, пул добирається рештою. Точкові кольори з фото не чіпаються —
    # там варіація неперервна й справжня.
    вийшло, бачені, бачені_слова, решта = [], set(), set(), []
    for d, r, q in підходящі:
        ключ = r.get("group_id") or r.get("id")
        if ключ in бачені: continue          # одна модель — один кандидат
        слово = ((r.get("колір_ім"), r.get("колір_модифікатор"))
                 if r.get("джерело_кольору") == "назва_вікно" and r.get("колір_ім") else None)
        if слово is not None and слово in бачені_слова:
            решта.append((d, r, q)); continue
        бачені.add(ключ)
        if слово is not None: бачені_слова.add(слово)
        вийшло.append(dict(r, _відстань=d, _вікно=q, _гілка=ГІЛКА_ЯДРО))
        if len(вийшло) >= K_НА_СЛОТ: break
    for d, r, q in решта:
        if len(вийшло) >= K_НА_СЛОТ: break
        ключ = r.get("group_id") or r.get("id")
        if ключ in бачені: continue
        бачені.add(ключ)
        вийшло.append(dict(r, _відстань=d, _вікно=q, _добрано_за_словом=True, _гілка=ГІЛКА_ЯДРО))
    return вийшло, None


# ── ОБОВ'ЯЗКОВИЙ СЛОТ СЦЕНАРІЮ НЕ БУВАЄ ПОРОЖНІМ, ПОКИ РЕЧІ В КАТАЛОЗІ Є ─────
# `pipeline.структура_образу` блокує образ без верху й низу (або без сукні), а
# `pipeline.пакет_для_моделі` пише моделі `обмеження.обов'язкові_слоти` =
# взуття + сумка на всякій нагоді, крім спорту, пляжу й дому. Отже ці слоти —
# не «бажано», а умова існування образу, і пул мусить їх нести.
# ЩО БУЛО ЗЛАМАНО (виміряно 17.09.2026, `проби/shvydkist_квоти.py`, каталог_brief
# — той самий фід, що їде в артефакт). Після K-PAL вікна звузились до 100 %
# влучань, і на всіх ШЕСТИ гілках стенда слот «низ» давав 2 речі — при 33 низах у
# каталозі, при поясі 29 і шарфі 29. `МІН_У_ДУЗІ` доповнює слот запасною хвилею,
# але запасна хвиля — теж вікна: коли й вона порожня, слот лишається на двох, і
# жінка дістає образ, у якому низ не вибирають, а беруть який є.
# ЩО РОБИТЬСЯ ТУТ. Останній ярус: речі слота БЕЗ колірного критерію, дедупліковані
# по моделі, позначені `_доповнено` — тобто пакет напише їм `у_дузі: false`, а
# модель побачить, що це вихід за палітру, а не її ядро. Мовчазної підміни нема:
# поле їде до моделі, нота — на екран.
# ЧОМУ НЕ ПРОСТО ОПУСТИТИ ПОРІГ ВІКОН: вікна — це вибір людини, і розширювати їх
# заради лічби означало б одягати її не в її кольори й не сказати про це.
# ЧИСЛО ОДНЕ НА ДЕРЕВО: його читають два яруси гарантії — добір кандидатів тут і
# вага квоти в `семплер` — і два літерали розійшлись би на першій же правці.
# Живе воно в `семплер` (модуль-лист, нічого проєктного не імпортує), а тут стоїть
# ім'я, щоб викликачі пулу не мусили знати про семплер.
# ПЕРЕЛІК обов'язкових слотів тут НЕ дублюється: він один і лежить у
# `bridge._обовязкові_слоти`, бо залежить від НАГОДИ, якої композитор не читає.
МІН_ОБОВЯЗКОВОГО = _СМ.МІН_ОБОВЯЗКОВОГО


def добір_слота(каталог, слот, наявні=(), скільки=МІН_ОБОВЯЗКОВОГО, сід=0):
    """Речі слота ПОЗА колірним критерієм — щоб обов'язковий слот не був порожнім.

    Той самий механізм, що й фолбек порожніх вікон у `_кандидати_на_слот`
    (дедуплікація по `group_id` проти модального колапсу, перемішування сідом,
    бо порядок фіду змісту не несе), тільки застосований до слота, який НЕ
    порожній, а бідніший за `МІН_ОБОВЯЗКОВОГО`. Відсічення сюди не входять —
    їх накладає викликач тим самим `pipeline.відсікти_пул`, що й на решту пулу.
    """
    бач = set()
    for r in наявні or ():
        бач.add(r.get("group_id") or r.get("id"))
        бач.add(r.get("id"))
    вийшло = []
    у_слоті = [r for r in (каталог or []) if r.get("слот") == слот]
    _перемішати(у_слоті, сід, слот + "|добір")
    for r in у_слоті:
        к = r.get("group_id") or r.get("id")
        if к in бач or r.get("id") in бач:
            continue
        бач.add(к); бач.add(r.get("id"))
        вийшло.append(dict(r, _відстань=None, _вікно=None, _гілка=ГІЛКА_ЯДРО,
                           _доповнено=True, _добір_обовязкового=True))
        if len(вийшло) >= скільки:
            break
    return вийшло


def добір_дуги(каталог, слот, дуга, C_min=0.0, наявні=(), скільки=МІН_ОБОВЯЗКОВОГО, сід=0):
    """Речі слота В НАЗВАНІЙ ДУЗІ ТОНУ — підлога кандидатів для обраного кольору.

    ТОЙ САМИЙ ЯРУС, ЩО Й `добір_слота`, І З ТІЄЇ САМОЇ ПРИЧИНИ, лише інша умова
    порожнечі. `добір_слота` рятує слот, якого в образі не може не бути (взуття,
    сумка); ця функція рятує ОБІЦЯНКУ, якої в образі не може не бути: жінка обрала
    основу, схема обіцяла їй «нейтралі + один акцент», і слот акценту, у якому
    жодної речі її кольору нема, робить обидві обіцянки невиконанними ще до того,
    як модель почне складати.
    ЧОМУ НЕ ЧЕРЕЗ ВІКНА. Вікно основи вже стоїть у `palette.запит_у_фід` і працює
    (вимір 19.09: 0 → 26 речей сім'ї в пакеті). Але вікно — це ДУГА × СМУГА
    СВІТЛОТИ × СМУГА ХРОМИ, і слот, чия смуга світлоти вузька, може лишитись
    порожнім при повному каталозі. Тут лишається сама дуга й нижня межа хроми
    (акцент мусить нести колір), решта меж знімається — і це названо: речі йдуть
    позначені `_доповнено`, як і всякий добір повз вікна.
    ⚠ ЦЕ НЕ РОБИТЬ КОЛІР ОБОВ'ЯЗКОВИМ. Функція кладе речі В ПУЛ; узяти їх чи ні —
    рішення моделі, а чи виконано обіцянку схеми — суд (`palettes.обіцянка_схеми`).
    Відсічення сюди не входять: їх накладає викликач тим самим `відсікти_пул`.
    """
    import colorspace as _КС
    lo, hi = float(дуга[0]), float(дуга[1])
    бач = set()
    for r in наявні or ():
        бач.add(r.get("group_id") or r.get("id")); бач.add(r.get("id"))
    у_слоті = []
    for r in (каталог or []):
        if r.get("слот") != слот or not r.get("lab"): continue
        try: L, C, h = _КС.lch(r["lab"])
        except Exception as _e:
            import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
            if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
            continue
        if C < float(C_min): continue
        if not ((lo <= hi and lo <= h <= hi) or (lo > hi and (h >= lo or h <= hi))): continue
        у_слоті.append(r)
    _перемішати(у_слоті, сід, слот + "|дуга")
    вийшло = []
    for r in у_слоті:
        к = r.get("group_id") or r.get("id")
        if к in бач or r.get("id") in бач: continue
        бач.add(к); бач.add(r.get("id"))
        вийшло.append(dict(r, _відстань=None, _вікно=None, _гілка=ГІЛКА_ЯДРО,
                           _доповнено=True, _добір_акценту=True))
        if len(вийшло) >= скільки: break
    return вийшло
