_ЗАПАС_КАЗУАЛЬНОГО = 3      # ф_фото ≤ lo − 3 → казуальне для цієї нагоди
_ЗАПАС_ОШАТНОГО = 2         # ф_фото ≥ hi + 2 → ошатне для цієї нагоди
