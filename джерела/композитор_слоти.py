def _нота_слота(*частини):
    """Нота слота з кількох причин одним рядком; None, коли сказати нема чого.

    Причин у слоті буває дві (бажаний метал і ошатність нагоди), і доти друга
    затирала б першу: обидві пояснюють ту саму лічбу пулу, тож губити одну
    заради іншої — те саме мовчання, від якого нота й заводилась."""
    з = [str(ч).strip() for ч in частини if ч and str(ч).strip()]
    return " · ".join(з) or None


