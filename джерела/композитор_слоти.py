def _вікна_на_межі(F, слоти, intent, вікна_ядра, source="uncontrolled", дистанція=None):
    """Вікна всіх гілок розвилки цієї людини, крім тієї, чиї вікна вже є ядром.
    Statement-гілки (тріада) — лише під statement/editorial. Схема без специфікації
    (контраст-мисматч) мовчить, а не вигадує вікна."""
    import palette as P
    # П.14 (СТАНДАРТ §4): `palette.розвилка` кидає ValueError і САМ називає, чого
    # бракує («нема рівня контрасту в профілі особи»). Доти його ковтав
    # `except Exception` і віддавав [] — гілок на межі не було, і про причину не
    # дізнавався ніхто. Тепер він летить у `bridge.виклик`; показ пише рядок
    # жінці (`ЗБ.діагноз`, `показ.html:5565`). Щасливий шлях не змінився.
    р = P.розвилка(O.контраст_особи(F), intent)
    ключ = lambda q: (q.get("слот"), q.get("L_min"), q.get("L_max"), q.get("C_min"), q.get("C_max"), q.get("h_from"), q.get("h_to"))
    ядро = {ключ(q) for q in (вікна_ядра or []) if isinstance(q, dict)}
    out = []
    for g in р["гілки"]:
        # ── ЦЕЙ ГЕЙТ НЕ Є ЗАМКОМ НА ВИБІР ЖІНКИ (перевірено 21.09.2026, рядок 117) ──
        # Правило «явний запит викликача сильніший за мапу» (див. `зібрати` нижче)
        # тут ні до чого — і ось чому, щоб наступна сесія не додавала сюди `явні`
        # наосліп. Функція віддає вікна ІНШИХ гілок, ніж ядро, а ядро — це рівно
        # та схема, яку обрала людина (`bridge._пакет_каталогу`: `_схеми` =
        # обрана гілка, `вікна` = союз її специфікацій). Отже обрана гілка не
        # може бути тут відсіяна цим рядком: до нього вона доходить лише як
        # ядро, а ядро відкидається трьома рядками нижче в будь-якому разі.
        # Рядок вирішує ЛИШЕ одне: чи тягнути statement-гілки в межу як ЧУЖІ
        # вікна під сміливим, але не statement-наміром. Це рішення коду про себе,
        # не про людину, — тож лишається як було.
        if g.get("вага") == "statement" and intent not in ("statement", "editorial"): continue
        # ГІЛКА БЕЗ ВЛАСНОЇ СПЕЦИФІКАЦІЇ НАЗИВАЄТЬСЯ УМОВОЮ, А НЕ ВИНЯТКОМ (п.14).
        # Доти `palette.СХЕМИ` не знала «контраст-мисматчу» ЗА ЗАДУМОМ, `специфікація`
        # на ньому чесно кидала ValueError, і його ковтав `except Exception … continue`
        # РАЗОМ із будь-якою справжньою поломкою: задум і поломка виглядали однаково
        # (виміряно `проби/vyniatky_103a.py`: 2 із 6 гілок живого шляху). Умова лишилась,
        # виняток — ні.
        # ВІДКОЛИ МИСМАТЧ УМІЄ ВІКНА (21.09.2026, рядок 122), умова його ВСЕ ОДНО не
        # пускає — і це рішення, а не залишок. `_вікна_на_межі` тягне вікна інших
        # СХЕМ, тобто інші ДУГИ ТОНУ: вихід за палітру по тону — законна межа сміливого
        # наміру. Мисматч інших дуг не має (він бере тони базової схеми) — він має іншу
        # ДРАБИНУ СВІТЛОТИ. Підмішати його вікна в пул означало б покласти в один образ
        # речі з двох різних драбин, тобто зламати ту, яку жінка обрала, — і K-COL-01
        # з K-CLR-02 потім судили б саме цю мішанину. Мисматч діє тоді й лише тоді,
        # коли його названо поіменно (`bridge._пакет_каталогу` → `специфікація`).
        # Виміряно, чому це не «про всяк випадок»: з мисматчем у межі `досяжність.py`
        # давала інший живий шлях (66 838 403 виклики проти 66 511 728, `добір_дуги`
        # переставав спрацьовувати) — тобто пул мінявся жінкам, які мисматчу не обирали.
        if g["схема"] not in P.СХЕМИ: continue
        вікна = [q for q in P.запит_у_фід(P.специфікація(F, g["схема"], слоти, source=source,
                                                         дистанція=дистанція))
                 if isinstance(q, dict) and q.get("L_min") is not None]
        if вікна and all(ключ(q) in ядро for q in вікна): continue      # це і є ядро
        out += [dict(q, _схема=g["схема"], _вага=g.get("вага")) for q in вікна if ключ(q) not in ядро]
    return out


def _влучає(r, q):
    """частка вікна (річ-зона) або точкове влучання; None — річ без кольору."""
    # П.14: lab і вікно речі народжує `фід_каталог` (трійка float або None), і
    # `None` тут уже названо рядком вище. Ковтати решту означало б віддати
    # «річ без кольору» на зламаний вимір — вони були невідрізненні.
    if not r.get("lab"): return None
    if r.get("вікно"):
        return feed.частка_вікна(r["вікно"], q)
    return 1.0 if feed.підходить(r["lab"], q) else 0.0


def _кандидати_гілки(речі, вікна, слот, ядро_ід, гілка, K, сід=0):
    """K речей слота, що влучають у ці вікна, але не в ядро; тег гілки і схема.

    Нічия розв'язується сідом, не порядком каталогу — та сама правка, що в
    `_кандидати_на_слот`; тут вона тримає гілку «на межі» в тому ж режимі, інакше
    сміливий намір лишився б детермінованим при випадковому ядрі."""
    у_слоті = [r for r in речі if r.get("слот") == слот]
    # ДВІ ХВИЛІ (Н-palette-2-098): запасне вікно (`спроба==1`, якірна нейтраль і
    # принт-ехо) не додає кандидатів, поки є хоч один із основного. Те саме
    # правило, що в `feed.покриття`, і той самий поділ — `feed.хвилі`.
    def _збір(вік):
        """(відстань, річ, вікно) для кожної речі слота, що влучає в одне з вікон `вік`."""
        out = []
        for q in вік:
            if q.get("слот") and q["слот"] != слот: continue
            for r in у_слоті:
                ч = _влучає(r, q)
                if not ч: continue
                d = (1.0 - ч) * 100.0 if r.get("вікно") else feed.відстань_до_центру(r["lab"], q)
                out.append((d, r, q))
        return out
    _осн, _зап = feed.хвилі(вікна)
    підходящі = _збір(_осн) or _збір(_зап)
    _перемішати(підходящі, сід, слот + "|межа")
    підходящі.sort(key=lambda x: x[0])
    вийшло, бачені = [], set(ядро_ід)
    for d, r, q in підходящі:
        к = r.get("group_id") or r.get("id")
        if к in бачені: continue
        бачені.add(к)
        вийшло.append(dict(r, _відстань=d, _вікно=q, _гілка=гілка, _схема=q.get("_схема")))
        if len(вийшло) >= K: break
    return вийшло


def _поза_палітрою(речі, вікна_усі, слот, зайняті, сід=0):
    """Речі слота з кольором, що не влучають у ЖОДНЕ вікно, — найдальші від палітри перші.

    Нічия — сідом (див. `_кандидати_на_слот`): «найдальші перші» теж дає плато
    рівних відстаней, і перший у фіді ставав єдиним дозволеним розривом."""
    у_слоті = [r for r in речі if r.get("слот") == слот and r.get("lab")]
    центри = [q for q in вікна_усі if not q.get("слот") or q["слот"] == слот]
    out, бачені = [], set(зайняті)
    for r in у_слоті:
        к = r.get("group_id") or r.get("id")
        if к in бачені: continue
        if any((_влучає(r, q) or 0) > 0 for q in центри): continue
        # П.14: `continue` тут викидав річ із розриву мовчки — той самий вхід
        # (lab речі, центри вікон), що й у `_влучає` рядком вище.
        d = min(feed.відстань_до_центру(r["lab"], q) for q in центри) if центри else 0.0
        бачені.add(к)
        out.append(dict(r, _відстань=d, _вікно=None, _гілка=ГІЛКА_РОЗРИВ))
    _перемішати(out, сід, слот + "|розрив")
    out.sort(key=lambda r: -(r["_відстань"] or 0))
    return out


def _своя_мова(r, реєстр_людини):
    """Чи належить річ хоч одному з реєстрів, які назвала людина (K-REG-02).

    М'ЯКА ПЕРЕВАГА, А НЕ ВОРОТА, І НЕ ЗМІНА КОЛІРНОЇ ОСІ. Правило прямо
    забороняє робити з реєстру людини фільтр («не `hard`: людина, що назвала
    „класика“, має право на одну цитату з іншого реєстру»), тому річ чужого
    реєстру звідси НЕ зникає. Але й посунути її нижче за колірним балом не
    можна: docstring `_кандидати_на_слот` обіцяє, що порядок МІЖ різними `d` не
    змінюється ні на йоту. Лишається рівно одне місце, де перевагу видно й де
    вона нічого не коштує, — НІЧИЯ. Сьогодні її розв'язує сід, тобто монета;
    реєстр людини — краща підстава за монету й гірша за колір, і саме там він
    і стоїть."""
    if not реєстр_людини:
        return False
    # П.14: `реєстри.реєстр_речі` — свій модуль над своєю річчю; False у
    # відповідь на його поломку означало б «реєстр не збігся», тобто НЕПРАВДУ
    # рівно в тому місці, задля якого цей розвʼязувач нічиєї й написано.
    import реєстри as _РЕ
    return bool(set(_РЕ.реєстр_речі(r).get("бали") or {}) & set(реєстр_людини))


# ── БАЖАНІ ПРИКРАСИ З ЦИМ ОБРАЗОМ (рядок 108, 20.09.2026; рядок 120, 21.09.2026) ──
# Класи — ті самі, що в суді (`суд_блиск.МЕТАЛИ_ТЕПЛІ/ХОЛОДНІ`): «золото» = теплі
# метали, «срібло» = холодні. Решта слів металу НЕ називає, і клас їм не вигадується.
_МЕТАЛ_КЛАС_БАЖАННЯ = {"золото": "теплий", "срібло": "холодний"}
# Слова, для яких «метал» — не відповідь: пул уміє лише підняти вперед речі БЕЗ слова
# металу, і нота каже, чого саме код не звірив. ВИМІРЯНО 21.09.2026 на `каталог_повний`
# (12 405 оферів, 260 ювелірних): слово металу несуть 139; сирий рядок складу називає
# перли чи перламутр на 8 (з них 7 — камінь на металевій оправі), а дерево, кістку чи
# бісер — на 0. Отже «перли» й «етно» розрізнити НЕМА ЧИМ, і поле роду прикраси в
# картці речі не пише ніхто: пункт A11 `суд_чеклісти.ЧЕКЛІСТ_АКСЕСУАРІВ` стоїть «без
# входу» з названим полем, а не вдає, ніби добір їх розрізнив.
_БЕЗ_КЛАСУ_МЕТАЛУ = {
    "перли": "перли — не метал; фід роду каменя в картку речі не пише",
    "етно":  "етно (дерево, кістка, бісер) — у каталозі таких прикрас 0",
    "інші":  "інші (будь-що без металу) — фід перлів і дерева окремо не пише",
}


def _клас_металу(м):
    """«теплий» / «холодний» / «міст» / None — з тих самих списків, що читає суд."""
    if not м:
        return None
    from суд_блиск import МЕТАЛИ_ТЕПЛІ, МЕТАЛИ_ХОЛОДНІ
    if м in МЕТАЛИ_ТЕПЛІ: return "теплий"
    if м in МЕТАЛИ_ХОЛОДНІ: return "холодний"
    return "міст"


def _за_бажаним_металом(у_слоті, слот, прикраси):
    """(речі, нота) — пул ювелірного слота під її бажання про прикраси З ЦИМ образом.

    Бажання жінки переважає рекомендацію за температурою (`палітра_температура`):
    це її рішення про сьогодні, не про те, що їй до лиця. Річ ПРОТИЛЕЖНОГО класу
    металу з пулу знімається (з лічбою в ноті), річ без слова металу лишається — фід
    називає метал лише в 40 % прикрас, і мовчання фіду не є «іншим металом».
    `_БЕЗ_КЛАСУ_МЕТАЛУ` («перли», «етно», «інші») — перевага речам без слова металу;
    коли після зняття лишилось би менше за `МІН_У_ДУЗІ`, знімати нічого не знімаємо, а
    лише ставимо зняте в кінець — щоб слот не спорожнів через її ж слово. Поза
    ювелірними слотами і без бажання — як доти.

    ── ЩО НОВЕ СЛОВО МІНЯЄ В РІШЕННІ, А ЩО ПОКИ НІ (рядок 120, 21.09.2026) ──────
    МІНЯЄ: «без прикрас» спорожнює ювелірний слот НАЗВАНО (нота нижче), а не через
    брак каталогу; «перли», «етно» й «інші» піднімають у пулі речі без слова металу
    рівно так само, як «інші» доти, — тобто нижче за золото/срібло за силою, але це
    все, на що фід дає підставу.
    НЕ МІНЯЄ: «перли» від «етно» пул НЕ відрізняє — рід не-металу в картці речі не
    пише ніхто (вимір — біля `_БЕЗ_КЛАСУ_МЕТАЛУ`). Два різні слова жінки дають тут
    той самий пул, і нота це каже вголос, а суд додає пункт A11 «без входу»: мовчазна
    рівність двох різних бажань була б тим самим, що вигаданий клас."""
    import feed as _Ф
    if not прикраси or слот not in _Ф._МЕТАЛ_СЛОТИ or not у_слоті:
        return у_слоті, None
    # «БЕЗ ПРИКРАС» — СЛОВО, ЯКЕ ПУЛ УМІЄ ВИКОНАТИ ЦІЛКОМ. На живому шляху сюди не
    # доходить (`композитор_збирання` знімає ювелірні слоти з переліку ще до добору),
    # але викликач, що кличе добір слота напряму, мусить дістати ТЕ САМЕ рішення, а не
    # повний пул прикрас: інакше одне й те саме її слово означало б різне у двох дорогах.
    if прикраси == "без прикрас":
        return [], ("слот ЗНЯТО за її словом «без прикрас»: %d речей прибрано з пулу — "
                    "це її рішення про сьогодні, не брак каталогу" % len(у_слоті))
    if прикраси in _БЕЗ_КЛАСУ_МЕТАЛУ:
        без = [r for r in у_слоті if not r.get("метал")]
        з_металом = [r for r in у_слоті if r.get("метал")]
        return без + з_металом, ("прикраси «%s»: %d речей без слова металу поставлено попереду %d із "
                                 "названим — %s, тож далі за метал код тут не бачить"
                                 % (прикраси, len(без), len(з_металом), _БЕЗ_КЛАСУ_МЕТАЛУ[прикраси]))
    клас = _МЕТАЛ_КЛАС_БАЖАННЯ.get(прикраси)
    if not клас:
        return у_слоті, None
    свої = [r for r in у_слоті if _клас_металу(r.get("метал")) == клас]
    без = [r for r in у_слоті if not r.get("метал") or _клас_металу(r.get("метал")) == "міст"]
    проти = [r for r in у_слоті if r not in свої and r not in без]
    if len(свої) + len(без) >= МІН_У_ДУЗІ:
        return свої + без, ("прикраси «%s» за її словом: у слоті %d речей цього металу, %d без слова металу "
                            "лишено, %d протилежного металу знято з пулу" % (прикраси, len(свої), len(без), len(проти)))
    return свої + без + проти, ("прикраси «%s» за її словом: свого металу %d, без слова %d — замало, тож %d речей "
                                "протилежного металу лишено в кінці, не знято" % (прикраси, len(свої), len(без), len(проти)))


