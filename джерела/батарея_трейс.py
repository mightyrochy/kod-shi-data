"""ГЕЙТ E · ЯКІ РЯДКИ З ID ВИКОНАЛИСЬ (чисте перенесення з `gate_reach.py`, 19.09.2026).

Одна функція — `виконані_рядки`: під фільтрованим `sys.settrace` проганяє міст
із каталогом на всіх сценах і парах (гілка, намір), усі навмисні образи через
`перевірити_образ`, композитор і фід, і повертає множину (файл, рядок), яких
торкнулось виконання. Саме це число вирішує у звіті гейта (а) «мертве» проти
(б) «не простежується».
"""

import json
import os
import sys

from батарея_корпус import рядки_правил
from батарея_входи import БАТАРЕЯ, НАГОДИ, СЦЕНИ_ПОГОДИ, СЦЕНИ_ОБРАЗУ
from батарея_образи import НАВМИСНІ
from батарея_труба import _прогін_композитора, _прогін_фіду

def виконані_рядки(рядки_ID=None):
    """Які рядки з ID ПРАВИЛА справді виконались.

    ── ЦЕ ЧИСЛО ВИРІШУЄ (а) ПРОТИ (б), І ВОНО МІРЯЛО НЕ ТЕ ────────────────────
    ЩО ЦЕ МІНЯЄ В РІШЕННІ (правило 3, before/after; друге проходження, 17.09.2026).
    Розділ (а)/(б) у кінці звіту стоїть на ОДНІЙ цій функції: правило без сліду
    йде в «мертве», якщо жоден його рядок тут не виконався, і в «не
    простежується», якщо виконався. Батарея тут була ДВА ВИКЛИКИ — `палітри` і
    `запити`, один профіль, одна нагода, `гілка=0`, `conventional` — і, головне,
    БЕЗ КЛЮЧА `каталог`.
      before — `bridge.запити` заходить у `_пакет_каталогу` лише під
               `if d.get("каталог")` (bridge.py:938). Ключа тут не було, тож
               виклик не доходив ні до `composer.зібрати`, ні до `pipeline`
               пакета, ні до відбору речей. `перевірити_образ` і `від_моделі`
               не кликались ЖОДНОГО разу. Тобто рядок «правило мертве»
               виносився батареєю, яка не заходила в половину конвеєра.
               ЗМІРЯНО 17.09.2026: із 57 правил, що стояли в цьому розділі,
               рядка ТОРКНУВСЯ РІВНО ОДИН (K-PAL-13, і той у `palettes.py`).
               Решта 56 — `accessory.py`, `суд_образу.py`, `outer.py`,
               `реєстри.py`, `колір_образу.py`, `composer.py` — лежала ЗА
               межею цієї батареї цілком. Прилад, написаний ловити «правило
               звітується мертвим через мою батарею», робив рівно це сам, і
               на найгучнішому зі своїх рядків.
      after  — трейс іде по ТІЙ САМІЙ досяжності, що й звітні числа: міст із
               каталогом на всіх трьох ендпойнтах, обидві гілки, обидва наміри,
               усі нагоди й погодні сцени, `перевірити_образ` на всіх навмисних
               образах, композитор і фід. Профілів тут один, а не шість, і це
               сказано вголос: «не виконався» означає «не виконався НА ЦЬОМУ
               профілі при повній досяжності», а не «мертвий».

    ── ЧОМУ ЦЕ ТЕПЕР ВЗАГАЛІ ПІДЙОМНО ────────────────────────────────────────
    Старий докстрінг казав «sys.settrace дорогий, тож батарея тут коротка» — і
    це була правда про НЕФІЛЬТРОВАНИЙ трейсер: він записував кожен рядок кожного
    файлу (7 799 рядків на два виклики, з них 6 000+ у `enum`, `inspect`, `ast`,
    `_compiler` — тобто в бібліотеках, де правил нема за побудовою).
    Питання ж вузьке: чи виконався ХОЧ ОДИН рядок, на якому стоїть ID правила.
    Тому трейсер фільтрує на події `call`: кадр із файлу, у якому рядків правил
    нема, не трасується ПО РЯДКАХ узагалі (`return None`). ЗМІРЯНО: 17 навмисних
    образів без трейсу — 1.7 с, під фільтрованим — 2.7 с, тобто 1.6×, а не 40×.
    """
    import bridge
    рядки_ID = рядки_ID if рядки_ID is not None else рядки_правил(
        os.path.dirname(os.path.abspath(__file__)) or ".")
    цікаві = set()
    for т in рядки_ID.values():
        цікаві |= т
    файли = {ф for ф, _ in цікаві}
    бачені = set()

    def tracer(frame, подія, arg):
        """Трасувальник `sys.settrace`: на `call` вмикає порядкове трасування лише файлам із рядками правил, на `line` записує (файл, рядок) із `цікаві`."""
        # ФІЛЬТР НА `call`, А НЕ НА `line`: відкидати на `line` означало б
        # платити виклик Python-функції за кожен рядок бібліотек. Кадр, чий файл
        # рядків правил не має, не трасується зовсім.
        if подія == "call":
            return tracer if frame.f_code.co_filename in файли else None
        if подія == "line":
            к = (frame.f_code.co_filename, frame.f_lineno)
            if к in цікаві:
                бачені.add(к)
        return tracer

    # ── РУКА 1: МІСТ, І З КАТАЛОГОМ ───────────────────────────────────────────
    try:
        _каталог = __import__("feed").каталог_на_диску("каталог_brief.xml")
    except SystemExit:
        _каталог = None
    п0, риси0 = БАТАРЕЯ[0]

    def _виклик(нагода, гілка, намір):
        """JSON входу моста: перший профіль батареї з нагодою, гілкою й наміром (каталог — коли він є на диску)."""
        d = dict(зріст=168, вік=32,
                 обхвати=dict(плечі=98, груди=92, талія=72, стегна=100),
                 самозвіт=dict(метал="золото", барви="приглушені",
                               нейтраль="теплі", білий="теплий"))
        d.update(риси0)
        d.update(випадок="прогін гейта", намір=намір, сценарій=нагода,
                 **({} if _каталог is None else dict(каталог=_каталог)),
                 **({} if гілка is None else dict(гілка=гілка)))
        return json.dumps(d, ensure_ascii=False)

    # ── ПОКРИТТЯ ШЛЯХІВ, А НЕ МАТРИЦЯ (і чому це не послаблення) ─────────────
    # ЩО ЦЕ МІНЯЄ (правило 3, before/after). Спершу тут стояла повна матриця —
    # 11 нагод × 2 гілки × 2 наміри × 3 ендпойнти = 132 виклики ПІД ТРЕЙСОМ. І це
    # був не вимір, а ціна: питання цієї функції вузьке — «чи виконався ХОЧ ОДИН
    # рядок, на якому стоїть ID правила», — і відповідь на нього не залежить від
    # того, скільки РАЗІВ рядок виконався. Матриця купувала повторення.
    # ЩО МУСИТЬ БУТИ ПРОЙДЕНЕ, І ЧОМУ САМЕ ЦЕ:
    #   · КОЖНА сцена — по одному разу: погодні гілки (`outer`, `accessory`,
    #     `verify`) розводить рівно сцена, і пропустити одну означало б не пройти
    #     її гілку взагалі;
    #   · КОЖНА пара (гілка, намір) — по одному разу: `гілка=None` бере пул союзом
    #     усіх схем, а `statement` інакше входить у розвилку — це різні шляхи коду,
    #     і обидва вже коштували проєкту падінь (крок A5, крок A7).
    # Сцени від (гілка, намір) не залежать, і навпаки, тож добуток тут зайвий:
    # 11 + 3 = 14 наборів замість 44, тобто 42 виклики замість 132.
    # ЦІНА ПОМИЛКИ НЕСИМЕТРИЧНА Й ОБРАНА НАВМИСНО: якби якась гілка все ж залежала
    # від пари «сцена × намір», правило з неї потрапило б у «(а) мертве» — тобто
    # провал ГУЧНИЙ і видимий у звіті, а не тихе завищення покриття.
    _база = НАГОДИ[0]
    виклики = [_виклик(н, 0, "conventional") for н in НАГОДИ + СЦЕНИ_ПОГОДИ]
    виклики += [_виклик(_база, г, н) for г, н in ((0, "statement"),
                                                  (None, "conventional"),
                                                  (None, "statement"))]
    # ── РУКА 2: ЗІБРАНИЙ ОБРАЗ. Готується ДО `settrace`: підготовка тіла й
    # геометрії правил не виконує, а під трейсом коштувала б дарма.
    import fit as _ПС, areas as _ОБЛ
    F2 = тіло2 = None
    образи = []
    try:
        F2, _T, _з, _kw = bridge._збірка(dict(
            шкіра=["#deb295"], волосся=["#f1dbaa", "#dabf89", "#b09362"], очі="#759087",
            зріст=168, обхвати=dict(плечі=98, груди=92, талія=72, стегна=100)))
        профіль = _ОБЛ.профіль_тіла(168, dict(плечі=98, груди=92, талія=72, стегна=100))
        H = {nm: y for nm, y, _ in профіль}
        тіло2 = _ПС.тіло(168, dict(плечі=98, груди=92, талія=72, стегна=100,
                                   коліно=35.0, литка=36.0, щиколотка=22.0),
                         рівні_см={"пах": 75.6})
        образи = НАВМИСНІ(H)
    except Exception as _e:
        import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
        if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
        pass

    sys.settrace(tracer)
    try:
        import pipeline
        for s in виклики:
            for ім in ("чипи", "палітри", "запити"):
                try:
                    bridge.виклик(ім, s)
                except Exception as _e:
                    import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
                    if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
                    pass
        for _чому, речі in образи:
            for с in СЦЕНИ_ОБРАЗУ:
                try:
                    pipeline.перевірити_образ(F2, [dict(r) for r in речі],
                                              тіло=тіло2, **с)
                except Exception as _e:
                    import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
                    if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
                    pass
        if F2 is not None and тіло2 is not None:
            _прогін_композитора(F2, тіло2)
        _прогін_фіду()
    finally:
        sys.settrace(None)
    return бачені
