# МЕТАЛ_ЮВЕЛІРНА_ПЛОЩА стояв серед констант блиску (K-MAT-04), але його ЄДИНИЙ
# споживач — `бюджет_хроми` нижче: метал у ювелірному масштабі бюджету хроми не
# витрачає. Переїхав до споживача, значення не змінене.
МЕТАЛ_ЮВЕЛІРНА_ПЛОЩА = 0.05   # T3: до 5% поля — ювелірний масштаб, бюджету хроми не витрачає

def бюджет_хроми(E, F, intent=None):
    """K-COL-02 (+K-PC-04, +K-FCE-04). Рахуються не кольори, а ГУЧНІ елементи,
    і волосся/оправа входять у бюджет нарівні з речами."""
    # МЕТАЛ і бюджет хроми: виведення мусить залежати від ПЛОЩІ, а не бути суцільним.
    # Перша версія прибирала з бюджету КОЖНУ металеву річ — і золотий ламе-верх площею 30%
    # перестав бути гучним, хоч він саме колірний блок. Тому метал не витрачає бюджет лише
    # у ювелірному масштабі (менше за МЕТАЛ_ЮВЕЛІРНА_ПЛОЩА); більша площа рахується як усі.
    # `e["площа"]` тут завжди число: функція кличеться лише над `_з_площею(...)`
    def _метал_поза_бюджетом(e):
        """Чи елемент — метал ювелірного масштабу (площа < `МЕТАЛ_ЮВЕЛІРНА_ПЛОЩА`), що бюджету хроми не
        витрачає.

        Чому так: перша версія прибирала з бюджету кожен метал, і золотий ламе-верх
        на 30 % поля переставав бути гучним; поріг 5 % — T3."""
        return bool(e.get("метал")) and e["площа"] < МЕТАЛ_ЮВЕЛІРНА_ПЛОЩА
    # РАХУЮТЬСЯ РЕЧІ, НЕ КОЛІРНІ ЕЛЕМЕНТИ. Принтована сукня з трьома гучними кольорами
    # займала три слоти бюджету з двох і сама себе оголошувала «конфліктом хром».
    гучні = []
    # ГУЧНІСТЬ — ЧАСТКА ЗОНИ НАД ПОРОГОМ, НЕ БІТ (28.08.2026, graph.py). Колір зі
    # слова має C-вікно («бордо» 25–70): яка частина його лежить над hi_C — стільки
    # ваги елемент несе в бюджеті. Фото-точка лишається 0/1, як і було. Бюджет
    # тепер сума ваг, а не лічба, і поріг «> 2» той самий: два гучних із запасом
    # (2.0) не спрацьовують, а два з половинкою третього — спрацьовують.
    def _гучність(e):
        """Вага елемента в бюджеті хроми K-COL-02: частка C-зони слова над `C["hi_C"]` (0..1), для
        фото-точки 1/0 за `гучний`.

        Чому так: колір зі слова має вікно хроми («бордо» 25–70), і біт означав би
        «завжди або ніколи»; частка зони — міра над порогом (28.08.2026). `гучний`
        через .get: елементи приходять і від composer та приладів."""
        зона = e.get("C_зона")
        if зона and зона[0] is not None and зона[1] is not None and зона[1] > зона[0]:
            lo, hi = float(зона[0]), float(зона[1])
            return max(0.0, min(1.0, (hi - C["hi_C"]) / (hi - lo)))
        # `гучний` читається через .get: елемент може прийти не з `елементи()` —
        # composer і прилади кладуть свої dict-и, і KeyError тут означав би, що
        # правило валиться від чужого (законного) викликача
        return 1.0 if e.get("гучний") else 0.0
    for річ, група in _групи_речей(E).items():
        # ПОЛІТИКА СЕКЦІЇ: у бюджет входить лише ВИМІРЯНА площа над порогом. Раніше
        # стояло `(e["площа"] or 0) >= min_area` — той самий відбір, але з вигаданим
        # нулем усередині; число бралось із нізвідки, і це не було видно.
        свої = [e for e in _з_площею(група, C["min_area"])
                if _гучність(e) > 0 and not _метал_поза_бюджетом(e)]
        if not свої: continue
        головний = max(свої, key=lambda e: e["площа"])
        гучні.append(dict(хто=річ, C=головний["C"], h=головний["h"],
                          гучність=round(max(_гучність(e) for e in свої), 2),
                          площа=round(sum(e["площа"] for e in свої), 3),
                          сім_я=головний["сім_я"],
                          кольорів=len(свої)))
    # Площа волосся й оправи — теж ВИМІР, не константа. Раніше тут стояли 0.10 і 0.02:
    # та сама помилка, яку прибрано зі слотів. Площа береться з F["_пікселі"] (маска
    # волосся у видимому полі, лабораторія/зони_з_масок.build_zones); без неї площа невідома, і елемент
    # рахується в БЮДЖЕТ (лічба площі не потребує), але не входить у тест КОНФЛІКТУ,
    # який порівнює площі. Це записується у знахідку, а не замовчується.
    # Площа волосся приходить у ПІКСЕЛЯХ (F["_пікселі"]) — нормуємо тим самим полем,
    # що й одяг. Речі несуть `пікселів` лише коли площа виміряна з масок; на
    # геометричному шляху пікселів нема, і площа волосся лишається невідомою.
    пкс = F.get("_пікселі") or {}
    поле_px = sum(e.get("пікселів") or 0 for e in E)
    площі_особи = {}
    if поле_px and пкс.get("волосся"):
        разом = поле_px + (пкс.get("волосся") or 0) + (пкс.get("оправа") or 0)
        площі_особи = {k: round(v/разом, 3) for k, v in пкс.items() if v}
    for k, f in F.items():
        if k.startswith("_"): continue
        if k.startswith("волосся") and f.get("C", 0) >= C["hi_C"]:
            гучні.append(dict(хто="волосся (фарбоване)", C=f["C"], h=f.get("h"),
                              площа=площі_особи.get("волосся"), сім_я="—", джерело="K-PC-04"))
        if k == "оправа" and f.get("C", 0) >= C["hi_C"]:
            гучні.append(dict(хто="оправа", C=f["C"], h=f.get("h"),
                              площа=площі_особи.get("оправа"), джерело="K-FCE-04"))
    out, без_площі = [], []
    # РОЗПЛЕТЕНО ПІСЛЯ ГАРНЕСУ ПАР: K-PC-04 (фарбоване волосся) і K-FCE-04 (оправа)
    # раніше лише додавались у бюджет K-COL-02 і власного вердикту не мали — жодна
    # кількість пар не показала б, чи вони праві. Тепер кожне з них — окрема знахідка:
    # твердження «власний колір людини витрачає бюджет» перевіряється незалежно від
    # твердження «у образі забагато гучних речей».
    for g in гучні:
        # ── ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026) ────────────────
        # before: «фарбоване волосся працює як гучний елемент образу» — констатація
        # без жодної дії над ОДЯГОМ, а діяти можна тільки одягом: волосся жінка не
        # перефарбовує через рядок промпту. Що саме робити, стояло в `ремонт`
        # («лишити одяг у нейтралях або взяти акцент із сім'ї волосся»), і рівно це
        # поле промпт ремонту не друкує — ші діставала факт замість ходу.
        # after (справжній рядок прогону, волосся #b3202a):
        #   · фарбоване волосся працює як гучний елемент образу: одяг тримати
        #     в нейтралях або в сім'ї волосся [0.50]
        # Протилежної гілки в правила нема (умова одностороння: C* над порогом),
        # тому рядок один; напрям переписаний дослівно з `ремонт` цього ж виклику.
        #
        # ЧОМУ ТУТ ДВОКРАПКА, А НЕ ТИРЕ (ревізія 08.09.2026). Перша редакція цього
        # рядка починалась «фарбоване волосся — гучний елемент образу: …», і тире
        # стояло ЗВ'ЯЗКОЮ. Але `_репліка` (той самий файл) будує `для_стиліста`
        # як `суть.split(" — ")[0]` — вона ріже речення по ПЕРШОМУ тире, бо в решті
        # рядків тире відділяє припис, який репліці й не потрібен. На зв'язці той
        # самий різ лишав від речення голе «Фарбоване волосся.» — іменник без
        # присудка. Тому зв'язка тут словом («працює як»), а тире в цьому рядку
        # немає зовсім: те, що ріже інші суті по припису, це речення не чіпає.
        if g.get("джерело") == "K-PC-04":
            out.append(_зн("K-PC-04", "soft",
                "фарбоване волосся працює як гучний елемент образу: одяг тримати "
                "в нейтралях або в сім'ї волосся",
                [g["хто"]], f"C*{g['C']:.0f} ≥ {C['hi_C']:.0f} — волосся забирає слот "
                "акценту, і образ має рахувати його нарівні з річчю",
                ремонт="лишити одяг у нейтралях або взяти акцент із сім'ї волосся",
                ламається="природний рудий підпадає під той самий поріг, хоча "
                          "сприймається інакше — межа фарбованого/природного тут не міряється"))
        # ── ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026) ────────────────
        # before: «оправа гучна й стоїть у зоні обличчя» — два факти й жодного
        # наслідку. Наслідок стояв поруч у `чому` цього ж виклику («у бюджет
        # входить, але як пуант»), а `чому` до промпту не доїжджає; ремонту в
        # правила нема зовсім, бо оправу воно міняти й не пропонує. Тому ші читала
        # рядок як докір окулярам і не бачила єдиної дії, яка тут узагалі є, —
        # витратити решту бюджету акцентів деінде.
        # after (справжній рядок прогону, оправа #c2185b):
        #   · оправа гучна в зоні обличчя — слот акценту вже зайнятий нею [0.25]
        # Другої гілки в правила нема (умова одностороння: C* над порогом). Нічого
        # не дораховано: «слот акценту зайнятий» — це переказ `чому` цього ж виклику.
        if g.get("джерело") == "K-FCE-04":
            out.append(_зн("K-FCE-04", "hint",
                "оправа гучна в зоні обличчя — слот акценту вже зайнятий нею",
                [g["хто"]], f"C*{g['C']:.0f} ≥ {C['hi_C']:.0f} при малій площі: "
                "у бюджет входить, але як пуант, а не як маса",
                ламається="площа оправи не міряється, беруться пікселі зони, коли вони є"))
    _сума_гучності = round(sum(g.get("гучність", 1.0) for g in гучні), 2)
    if _сума_гучності > 2:
        out.append(_гейт_наміром(_зн("K-COL-02", "strong", f"{len(гучні)} високонасичених елементи (вага {_сума_гучності}) — понад бюджет",
            [g["хто"] for g in гучні], "решта образу не встигає бути тлом",
            ремонт="лишити один гучний як фокус; інші — приглушені версії тієї ж сім'ї "
                   "або нейтралі (K-COL-03: нейтрали+акцент)",
            вимір=_сума_гучності,
            ламається="дрібні аксесуари (сережки, пряжка) майже не витрачають бюджет — "
                      "поріг площі тут грубий",
            поріг=2), intent))
    # конфлікт хром: сам механізм «строкатості» — не кількість, а зіткнення
    for i in range(len(гучні)):
        for j in range(i+1, len(гучні)):
            g1, g2 = гучні[i], гучні[j]
            if g1.get("h") is None or g2.get("h") is None: continue
            if g1["площа"] is None or g2["площа"] is None:
                без_площі.append((g1["хто"], g2["хто"])); continue
            dh = abs(g1["h"] - g2["h"]); dh = min(dh, 360-dh)
            if dh >= 45 and g1["площа"] >= 0.10 and g2["площа"] >= 0.10:
                out.append(_гейт_наміром(_зн("K-COL-02", "strong", "конфлікт хром: два гучні кольори "
                    "співмірної площі б'ються за увагу", [g1["хто"], g2["хто"]],
                    f"Δтон {dh:.0f}°, площі {g1['площа']} і {g2['площа']} — два фокуси гасять один одного (K-CRA-02)",
                    ремонт="зменшити площу одного до аксесуара АБО приглушити (взяти темнішу/"
                           "знесиченішу версію того ж кольору)",
                    ламається="приглушена комплементарна пара (бордо+хвойний) працює саме тому, "
                              "що одна сторона затемнена — тоді це не конфлікт",
                    поріг=45, вимір=dh), intent))
    if без_площі:
        out.append(dict(правило="K-COL-02", сила="утримано",
            сила_нп=None, сила_нп_джерело="виміру нема (утримано): без площ бюджет не рахується",
            суть="тест конфлікту хром пропущено для пар без виміряної площі",
            речі=sorted({x for пара in без_площі for x in пара}),
            чому="площа волосся/оправи не подана у F[\"_пікселі\"]; лічба бюджету її не потребує, "
                 "а порівняння площ — так",
            ремонт="подати F[\"_пікселі\"] з лабораторія.зони_з_масок.features_from_zones(build_zones(...))"))
    return out

def сім_ї_образу(E, intent=None):
    """K-COMP-03: ≤3 колірні сім'ї (нейтралі рахуються м'яко)."""
    # політика секції: у лічбу сімей входить лише виміряна площа над порогом
    кольорові = {e["сім_я"] for e in _з_площею(E, C["min_area"]) if not e["нейтраль"]}
    if len(кольорові) > 3:
        return [_гейт_наміром(_зн("K-COMP-03", "soft", f"{len(кольорові)} колірні сім'ї — понад ліміт",
                    sorted(кольорові), "образ втрачає впізнавану палітру",
                    ремонт="звести дві сусідні сім'ї до однієї або перевести одну в нейтраль",
                    вимір=len(кольорові),
                    ламається="принт із багатьма кольорами — одна сім'я за домінантою, не N",
                    поріг=3), intent)]
    return []

БЕЗ_СТЕЛІ_ВІДЛУННЯ = ("тональна", "аналогова")

def відлуння(E, фокус=None, intent=None, схема=None):
    """K-COL-05 + стеля з ремесла. Акцент або повторюється, або є свідомим фокусом.
    Сирота-акцент читається як шум; 4+ повтори — знову matchy."""
    out = []
    # ЗНАЙДЕНО ЗАМКНЕНИМ ЦИКЛОМ: аналогова схема (тони 200°, 230°, 255°) розпадалась
    # на «синьо-зелену» і «синю» сім'ї, і третій сусідній тон ставав «сиротою-акцентом».
    # Сусідні тони — один голос, а не два: тверді межі сімей годяться, щоб РАХУВАТИ
    # сім'ї (K-COMP-03), і не годяться, щоб шукати відлуння. Групуємо за дугою.
    СУСІДНІ = 45.0        # T3: у межах цієї дуги кольори читаються як один акцент
    # БУЛО: групи лежали в dict із КЛЮЧЕМ-СІМ'ЄЮ. Сім'ї широкі (червона/рожева 340–45°,
    # синьо-зелена 180–250°), тож дві речі однієї сім'ї легко стоять далі ніж 45° одна від
    # одної — і другий запис МОВЧКИ ЗАТИРАВ перший разом з усіма його знахідками.
    # Відтворено: акцент, який окремо давав «сироту» strong, зникав безслідно.
    групи = []            # [dict(назва, члени)] — список, ключів більше нема
    # ── НЕВИМІРЯНИЙ ЕЛЕМЕНТ ДО ГРУПУВАННЯ НЕ ВХОДИТЬ, І ЦЕ КАЖЕТЬСЯ (Н-outfit-1-084)
    # Тут стояло `(x["площа"] or 0) >= 0.01` і `-(x["площа"] or 0)`: невиміряна площа
    # ставала нулем, елемент мовчки випадав із відлуння (0.0 < 0.01) — а нижче
    # `sum(e["площа"] for e in es)` усе одно падав TypeError, якщо він проходив іншою
    # гілкою. Дві реакції на один стан в одній функції. Тепер відбір один (`_з_площею`),
    # а ті, кого не порахували, виходять ОКРЕМОЮ знахідкою «утримано»: акцент над
    # річчю без площі не судиться, і ніхто не читає цю тишу як «акценту нема».
    невиміряні = sorted({e["річ"] for e in _без_площі(E) if not e["нейтраль"]})
    if невиміряні:
        out.append(dict(правило="K-COL-05", сила="утримано",
            сила_нп=None, сила_нп_джерело="виміру нема (утримано): площа цих речей не виміряна",
            регістр="утримано", блокує=False,
            суть="невиміряні речі до групування відлуння не входять — акцент над ними не судиться",
            речі=невиміряні,
            чому="відлуння ділить акценти на групи за тоном і міряє їхню площу проти "
                 "focus_area; елемент без виміряної площі не можна ні віднести до групи, "
                 "ні відсіяти як дрібний — тому він не рахується, і це сказано",
            ремонт="подати площі образу (areas.образ_з_масок або areas.образ_з_геометрії)"))
    for e in sorted([x for x in _з_площею(E, 0.01) if not x["нейтраль"]],
                    key=lambda x: -x["площа"]):
        for g in групи:
            d = abs(g["члени"][0]["h"] - e["h"]); d = min(d, 360-d)
            if d <= СУСІДНІ: g["члени"].append(e); break
        else:
            групи.append(dict(назва=e["сім_я"], члени=[e]))
    # якщо дві РІЗНІ групи носять те саме ім'я сім'ї — розрізняємо їх у тексті знахідки
    лічильник = {}
    for g in групи:
        лічильник[g["назва"]] = лічильник.get(g["назва"], 0) + 1
    вжито = {}
    for g in групи:
        if лічильник[g["назва"]] > 1:
            вжито[g["назва"]] = вжито.get(g["назва"], 0) + 1
            g["назва"] = "%s (тон ~%d°)" % (g["назва"], round(g["члени"][0]["h"]))
    for nm, es in [(g["назва"], g["члени"]) for g in групи]:
        зони = {e["слот"] for e in es}
        площа = sum(e["площа"] for e in es)
        if len(зони) == 1 and площа < C["focus_area"]:
            слот = list(зони)[0]
            свідомий = фокус and слот in фокус
            # ── СИЛА СИРОТИ-АКЦЕНТУ: strong → default ─────────────────────────
            # ТЕМА-4, K-COMP-05 (= K-COL-05), ПРОГІН 2 (05.09.2026), дослівно:
            # «FORCE: `default` — lowered from `strong`, run 2: the threshold "≥2"
            # has no source». Механізм (гештальтна подібність/повтор, фігура–тло
            # Рубіна) академічно справжній — але «щонайменше два рознесені носії»
            # виведене не з нього, а з ремесла. Сила стояла на порозі, якого
            # джерело не дає.
            # ЩО ЦЕ МІНЯЄ НАД РЕАЛЬНОЮ РІЧЧЮ: одна теракотова сумка без другого
            # теракотового носія перестає бути великим штрафом і стає малим,
            # оборотним — тобто образ із однією виразною річчю більше не програє
            # рангом лише за те, що акцент не повторено. Це той самий випадок,
            # який корпус називає ліцензованим винятком: statement-річ у фокусній
            # зоні. Гілка `свідомий` (оголошений фокус) як була `hint`, так і є.
            out.append(_гейт_наміром(_зн("K-COL-05", "hint" if свідомий else "default",
                f"акцент «{nm}» присутній в одній зоні і малий — сирота",
                [e["річ"] for e in es],
                f"площа {площа:.2f} < {C['focus_area']} і зона одна: око не знаходить наміру",
                ремонт=(f"фокусна зона оголошена ({слот}) — акцент легітимний як пуант"
                        if свідомий else
                        "повторити колір у другій рознесеній зоні (взуття↔сумка↔шарф↔помада) "
                        "АБО оголосити цю зону фокусом, АБО прибрати"),
                запит=None if свідомий else dict(слот="взуття|сумка|шарф|прикраси",
                     сім_я=nm, чому="другий носій акценту — найдешевший спосіб зібрати образ"),
                ламається="якщо зона оголошена фокусною і акцент там — це пуант, не шум; "
                          "без оголошеного фокусу відрізнити неможливо",
                поріг=C["focus_area"], вимір=площа), intent))
        # ЗНАЙДЕНО ЗАМКНЕНИМ ЦИКЛОМ: тональна схема кладе один тон у всі зони, і
        # стеля відлуння оголошувала її «matchy». Виняток був записаний у полі
        # «де ламається», але не діяв, бо гейт не знав, яку схему обрав композитор.
        # Тепер схема передається у review — це вхід, а не здогад.
        if len(зони) > C["echo_max"] and (схема not in БЕЗ_СТЕЛІ_ВІДЛУННЯ):
            out.append(_зн("K-COL-05", "soft", f"акцент «{nm}» повторено у {len(зони)} зонах — matchy",
                [e["річ"] for e in es], "повтор перестає читатись як намір і стає уніформою",
                ремонт="лишити 2–3 носії, решту перевести в нейтраль",
                вимір=len(зони),
                ламається="тональна колона одного кольору — інша схема (K-COL-03 §2), не відлуння",
                поріг=C["echo_max"]))
    return out
