# ── ЯК ЧИТАЄТЬСЯ БІК ────────────────────────────────────────────────────────
# Ремонту в знахідках країв нема (Е3: заміну пропонує лише спільне джерело після суду), тож бік
# береться з поля `заяви`: K-OUT-03 несе `direction`, K-OUT-43 — код придатності до ремонту.
_БІК_ЗА_КОДОМ = {"outer_longer": "вкоротити_верх", "outer_shorter": "змінити_низ",
                 "edge_violation_repairable": "вкоротити_верх", "edge_violation_terminal": "змінити_низ"}


def _знак_ремонту(з):
    """«вкоротити_верх» / «змінити_низ» / «—». Бік, який називає заява знахідки."""
    for заява in (з.get("заяви") or ()):
        бік = _БІК_ЗА_КОДОМ.get(заява.get("code")) or _БІК_ЗА_КОДОМ.get((заява.get("values") or {}).get("direction"))
        if бік:
            return бік
    return "—"


def _трійки(знахідки, правила=None):
    """((правило, регістр, знак), …) — у порядку появи, як їх бачить споживач."""
    return tuple((з.get("правило"), з.get("сила"), _знак_ремонту(з))
                 for з in знахідки
                 if правила is None or з.get("правило") in правила)


# ── ФІКСТУРИ: ДОВЖИНИ ВИРОБІВ ВІД ОДНІЄЇ ТОЧКИ, ДЖЕРЕЛО «виріб» ─────────────
# Бік і різницю країв код називає лише понад похибку обох (рішення менеджера 06.11 «факт замість
# межі», п.3): край зі слова, геометрії речі чи рівня тіла — частка зросту без похибки, тож вимір
# у фікстурі — довжина виробу від плечей (Ф-9) з допуском сітки `ДОПУСК_ДОВЖИНИ_ВИРОБУ_СМ`.
# Δ = довжина низу − довжина верхнього шару = край верхнього − край низу (знак `край_см`):
# Δ > 0 означає «край верхнього шару ВИЩЕ», тобто верхній шар КОРОТШИЙ.
_ТОЧКА = "плечі"


def _виміряна(**kw):
    дов = kw.pop("довжина", None)
    if дов is not None:
        kw.update(довжина_виробу_см=дов, довжина_виробу_точка=_ТОЧКА, край_джерело="виріб")
    return kw


def _пальто(довжина, **kw):
    return dict(_виміряна(id="п", слот="верхній_шар", назва="Пальто", тип="пальто",
                          тип_верхнього="пальто", довжина=довжина), **kw)


def _сукня(довжина):
    return _виміряна(id="с", слот="сукня", назва="Сукня", тип="сукня", довжина=довжина)


_ВЕРХ = dict(id="в", слот="верх", назва="Блуза", тип="блуза")


def _краї(Δ):
    """Пара речей із заданим Δ: сукня завдовжки 100.0 від плечей, верхній шар — 100.0 − Δ."""
    return [_пальто(round(100.0 - Δ, 1)), _сукня(100.0)]


def _боки(Δ):
    """Бік ремонту, який називають K-OUT-03 і K-OUT-43 на одному й тому ж витку."""
    зн = {з["правило"]: з for з in O.краї(_краї(Δ), None)}
    return tuple(_знак_ремонту(зн[п]) if п in зн else "нема"
                 for п in ("K-OUT-03", "K-OUT-43"))


def _сила_нп(Δ, правило):
    зн = {з["правило"]: з for з in O.краї(_краї(Δ), None)}
    return (зн.get(правило) or {}).get("сила_нп")


def _заяви(речі):
    return tuple(з["code"] for зн in O.краї(речі, None) for з in (зн.get("заяви") or ()))


