"""ПРИЛАД ШМАТКА `outer`: функції кличуться НАПРЯМУ, не через `перевірити`.

ЧОМУ ЦЕ ІСНУЄ (Н-outer-1-077). Батарея теми-11 кликала рівно одну точку —
`outer.перевірити()` — і судила вихід у цілому. Тому перевернутий знак Δ прожив
у `краї()` до 10.09.2026: у навмисному зимовому образі батареї пальто до литки
(33.6 см від підлоги) над сукнею до коліна (47.9) дає |Δ| = 14.3, тобто більше
за смугу близькості 10 см, і гілка не виконувалась узагалі. Одна точка входу не
може покрити гілки, які вмикаються ВУЗЬКИМИ значеннями; таблиця випадків може.

ЩО ФІКСУЄТЬСЯ. Не текст, а ТРІЙКА (правило, регістр, знак ремонту) — і числа,
які мають власний зміст (`сила_нп`, кроки каскаду, частка придушення). Тексти
`суть` / `чому` / `ламається` в цьому файлі переписуються майже кожним нарядом;
прилад, прив'язаний до них, був би червоним щоразу й нічого б не ловив.

ЄДИНЕ МІСЦЕ, ДЕ ПРИЛАД УСЕ Ж ЧИТАЄ СЛОВА, — `_знак_ремонту`: бік ремонту в
знахідці не закодований полем, він тільки в тексті першої опції. Це названо тут
вголос, а не сховано: коли з'явиться поле (напр. `бік`), класифікатор має піти.

ЗАПУСК:  python3 проба_outer.py       (код виходу 0 / 1, як у решти приладів)
"""
import os as _os
