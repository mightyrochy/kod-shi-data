def прогнати(друк=True):
    """Скільки випадків упало. Нуль — прилад зелений."""
    збої = []
    for мітка, рахунок, очікуване in ВИПАДКИ:
        try:
            факт = рахунок()
        except Exception as e:                      # виняток — теж провал випадку
            факт = "%s: %s" % (type(e).__name__, e)
        якщо_ок = факт == очікуване
        if not якщо_ок:
            збої.append((мітка, факт, очікуване))
        if друк:
            print(("  ✓ %s" % мітка) if якщо_ок
                  else ("  ✗ %s\n      вийшло:   %r\n      мало бути: %r"
                        % (мітка, факт, очікуване)))
    if друк:
        print("\nПРОЙДЕНО %d, ВПАЛО %d" % (len(ВИПАДКИ) - len(збої), len(збої)))
    return len(збої)


