"""Статус наявних фактів речі без нових фактів зі слів каталогу.

Договір: status = measured / range / unknown / not_applicable; value — сам факт,
source — його чинний писач. Явна відсутність є measured + absent, а не unknown
чи not_applicable. Матриця визначає застосовність, а не наявність значення.
Склад — склад речі загалом: правило «без тканини» не робить його NA.
"""
import внутрішня_мова as _ВМ
import колір_річ as _К
import colorspace as _cs
import palettes as _ПЛ

СТАТУСИ = ("measured", "range", "unknown", "not_applicable")
ВЛАСТИВОСТІ = ("color", "composition", "metal")

# Походження чинних правил, а не нова класифікація матеріалів. Поле металу поза
# ювелірними слотами дозволене фід_атрибути.МЕТАЛ_СЛОТИ_ПОЛЕ. В інших типах
# фурнітура можлива, її застосовність невідома, а не заперечена.
ДЖЕРЕЛА_МАТРИЦІ = {
    "color": "колір_річ.не_вимір/межі_кольору/точка_кольору",
    "composition": "пакет_моделі.річ_пулу; фід_атрибути.матеріал_речі; ПРОДУКТ п.16",
    "metal": "фід_атрибути.МЕТАЛ_СЛОТИ/МЕТАЛ_СЛОТИ_ПОЛЕ; траурний_регістр.метал_біля_обличчя",
}
_ЮВЕЛІРНІ = frozenset(("earrings", "necklace", "collar_necklace", "bracelet", "ring",
                        "brooch", "watch", "jewelry"))
_ТКАНИННІ = frozenset(("top", "bottom", "dress", "set", "outerwear", "scarf", "headwear",
                       "gloves", "tights", "socks", "underwear", "swimwear"))
МАТРИЦЯ = {
    тип: {"color": {"applicability": "applicable", "source": ДЖЕРЕЛА_МАТРИЦІ["color"]},
          "composition": {"applicability": "applicable" if слот in _ТКАНИННІ else "unknown",
                          "source": ДЖЕРЕЛА_МАТРИЦІ["composition"]},
          "metal": {"applicability": "applicable" if слот in _ЮВЕЛІРНІ | {"belt", "bag"} else "unknown",
                    "source": ДЖЕРЕЛА_МАТРИЦІ["metal"]}}
    for тип, слот in _ВМ.СЛОТ_ТИПУ.items()
}


def тип_кодом(річ):
    """Тип із чинного enum: код або ключ ядра; незнайоме не вгадувати з назви."""
    тип = річ.get("тип")
    return тип if isinstance(тип, str) and тип in _ВМ.ТАБЛИЦЯ["item_type"] else _ВМ.код("item_type", тип)


def факт(статус, значення, джерело):
    """Утворити факт із чотирма станами та явним походженням."""
    if статус not in СТАТУСИ or not джерело:
        raise ValueError("невідомий статус чи немає походження факту")
    if статус in ("unknown", "not_applicable") and значення is not None:
        raise ValueError("невідоме й NA не містять значення")
    if статус in ("measured", "range") and значення is None:
        raise ValueError("відомий факт потребує значення")
    return dict(status=статус, value=значення, source=джерело)


def властивість(річ, властивість):
    """Адаптувати чинні значення кольору, складу й металу до одного договору.

    Сирий склад не є цитатним розбором. Його наявність не доводить жодного коду
    складу; чисел/слів з нього тут не добуваємо. Колір рахує лише його власник.
    """
    if властивість not in ВЛАСТИВОСТІ:
        raise ValueError("незнайома властивість")
    if властивість == "color":
        if not _К.позначено_невідомим(річ):
            if _К.не_вимір(річ) is not None:
                межі = _К.межі_кольору(річ)
                if межі is not None:
                    return факт("range", межі, "color_window")
            elif ((річ.get("осі") or {}).get("L_from") in ("word", "word_or_photo")
                  or річ.get("джерело_кольору") == "назва_вікно"):
                # Старий запис уже втратив саме вікно: hex-центр не відновлює його.
                return факт("unknown", None, "color_provenance_missing")
            else:
                точка = _К.точка_кольору(річ)
                if точка is not None:
                    return факт("measured", точка, "color_point")
        return факт("unknown", None, "color_missing")
    if властивість == "metal":
        метал = річ.get("метал")
        код = метал if isinstance(метал, str) and метал in _ВМ.ТАБЛИЦЯ["metal"] else _ВМ.код("metal", метал)
        варіанти = річ.get("метал_варіанти")
        if isinstance(варіанти, (list, tuple)) and варіанти:
            коди = [v if isinstance(v, str) and v in _ВМ.ТАБЛИЦЯ["metal"] else _ВМ.код("metal", v) for v in варіанти]
            if all(коди):
                return факт("range", коди, "metal_variants")
        if код:
            return факт("measured", код, "metal_code")
        return факт("unknown", None, "metal_missing")
    if річ.get("склад_ненадійний"):
        return факт("unknown", None, "composition_unreliable")
    склад = річ.get("склад_коди")
    if склад:
        return факт("measured", list(склад), "composition_declared_codes")
    return факт("unknown", None, "composition_raw" if річ.get("матеріал") else "composition_missing")


def знання(річ):
    """Три факти разом із походженням застосовності для чинного коду типу."""
    тип = тип_кодом(річ)
    return {в: dict(властивість(річ, в), applicability=МАТРИЦЯ.get(тип, {}).get(в, {
        "applicability": "unknown", "source": ДЖЕРЕЛА_МАТРИЦІ[в]})) for в in ВЛАСТИВОСТІ}


def на_дріт(дані, має_точку=False):
    """Передати повні факти трьох властивостей до спільного codec промпту.

    Старі поля моделі лишаються. Значення діапазону кольору та відомого металу
    передаються окремо: центр колірного вікна не можна читати як вимір.
    """
    вих = {"knowledge": дані}
    if дані["color"]["status"] == "range":
        вих["color_range"] = дані["color"]["value"]
    elif дані["color"]["status"] == "measured" and not має_точку:
        вих["lab"] = дані["color"]["value"]
    if дані["metal"]["status"] in ("measured", "range"):
        вих["metal"] = дані["metal"]["value"]
    return вих


# ── ЩО ПРО РІЧ ЗНАЄ ПРОДУКТ — ОДИН СКЛАДАЧ ДЛЯ МОДЕЛЕЙ, ЩО ПИШУТЬ ЖІНЦІ (корінь Е2-опора-пояснення, п.1 і п.5) ──
# ПРОБЛЕМА. Під образом жінка читала про річ те, чого на фото нема: «коричнева» сумка — бордова, «чорний берет» — сірий,
# кремова сукня «зі срібним відтінком», «сірі штани вузького крою» — широкі прямі. Поля запису речі (колір, крій, тканина,
# довжина…) ішли у вхід опису образу, запасних заміни й перекладачки окремими писачами — як факт, хоч продукт мав про них
# лише слово крамниці, здогад з кадру чи кадр іншого варіанта; правило в промпті «властивість — із коду або з фото»
# лишало код опорою, навіть хибний (#3717, невдалий підхід паспорта).
# ПРАВИЛО. Кожна властивість речі має тут певність — звідки продукт її знає; у вхід моделі, що пише жінці, іде лише та,
# що певність має, і без позначки «не певний»: позначок у довгому вході мала модель не тримає (паспорт, рішення 16.11).
#   КОД      — факт самого коду: номер і кадри речі, половина комплекту, її річ, кадр картки іншого кольору;
#   ВИМІР    — колір, виміряний на кадрі речі (`колір_річ.тип_кольору` — «вимір»), коли кадр картки не іншого кольору:
#              hex і код його найближчої назви (`колір_кадру`), а не код слова крамниці;
#   ІМЕННИК  — вид речі (рід і тип): без іменника річ не назвати, тож він лишається, хоч позначки певності виду запис не
#              має — лише походження `тип_джерело` (назва, категорія, оголошене, розбір; дошка 16165, `Річ-запис-речі`).
# Не певне (None) і не йде: колір зі слова крамниці чи моделі (і без виміру, і поруч із ним), колір під кадром іншого
# кольору, ознаки запису (крій, тканина, матеріал, довжина, рукав, халява, каблук, візерунок, блиск, деталі) — слова
# крамниці чи здогад з кадру, жодну не звірено з доставленим кадром, тож запис речі опису їх більше не несе (писача
# `міст_опис._ознаки_речі` нема). Мовчати про них прийнятно: річ видно на фото.
КОД, ВИМІР, ІМЕННИК = "код", "вимір", "іменник"

# Тип чужого роду — не вужчий, а хибний: «В'язана шапка Одрі» — рід `headwear`, а тип класифікатор дав за
# прикметником: «светр» (`sweater`); опис, що читає «kind: headwear, type: sweater», пише пов'язку на голову. Винятки
# законні: половина комплекту (`set`), верх, що носиться верхнім шаром (кардиган, жилет — `top` ↔ `outerwear`), і
# прикраса без уточнення на будь-якому роді прикрас.
_РОДИ_ПОРУЧ = {frozenset(("top", "outerwear"))}
_РОДИ_ПРИКРАС = frozenset(("jewelry", "necklace", "collar_necklace", "bracelet", "earrings", "brooch", "ring"))
_ЧАСТИНА = {"верх": "top", "низ": "bottom"}


def тип_свого_роду(тип, рід):
    """Код типу, коли він не належить іншому роду за `СЛОТ_ТИПУ`; інакше None."""
    свій = _ВМ.СЛОТ_ТИПУ.get(тип or "")
    if (not тип or not рід or not свій or свій in (рід, "set") or frozenset((свій, рід)) in _РОДИ_ПОРУЧ
            or {свій, рід} <= _РОДИ_ПРИКРАС):
        return тип
    return None


def колір_кадру(x):
    """Код `color_name` кольору, виміряного на кадрі речі (`palettes.назва` її hex — те саме вікно, що підписує
    палітру), або None. Не код слова крамниці: слово вікно виміру приймає й тоді, коли кадр ближчий до іншого кольору
    (сумка «brown» з виміром `#4a2b2c` — бордова на фото, берет «black» з `#584c4d` — сірий), тож про колір каже кадр."""
    hx = _К.hex_кольору(x)
    if not hx:
        return None
    try:
        к = _ВМ.код("color_name", _ПЛ.назва(_cs.hx("#" + str(hx).lstrip("#")))[0])
    except ValueError:
        return None
    return к if к and not _ВМ.невідомо(к) else None


def певне(x):
    """Річ входу пояснення (`міст_опис`: слот, тип, частина, колір, код_кольору, hex, кадр_колір, фото_номери,
    без_кадру, її_річ; річ картки перекладачки — ті самі ключі) → {ключ дроту: значення} лише тих властивостей, які
    продукт знає. Кожна властивість, яку запис несе, стоїть тут із певністю; певність None — значення продукт не знає,
    і в модель воно не йде; порожнього теж нема."""
    рід = _ВМ.код("slot", x["слот"]) if x.get("слот") else None
    інший_кадр = bool(x.get("кадр_колір"))
    колір = ВИМІР if _К.тип_кольору(x) == "вимір" and not інший_кадр else None
    вих = {}
    for ключ, значення, певність in (
            ("kind", рід, ІМЕННИК),
            ("type", тип_свого_роду(_ВМ.код("item_type", x["тип"]) if x.get("тип") else None, рід), ІМЕННИК),
            ("set_half", _ЧАСТИНА.get(x.get("частина")), КОД),
            ("color", колір_кадру(x), колір), ("hex", _К.hex_кольору(x), колір),
            ("photo_other_colour", True if інший_кадр else None, КОД),
            ("photos", x.get("фото_номери"), КОД), ("no_photo", True if x.get("без_кадру") else None, КОД),
            ("hers", True if x.get("її_річ") else None, КОД)):
        if певність and значення not in (None, "", []):
            вих[ключ] = значення
    return вих
