def базова_для_мисматчу(особа, intent="conventional"):
    """Схема, в якої обраний мисматч бере ТОНИ: перша законна гілка розвилки цієї людини.

    ЧОМУ САМЕ ВОНА, А НЕ ВИБІР ЗІ СТЕЛІ. Мисматч — заява про СВІТЛОТУ, не про тон:
    «контраст образу свідомо не під контраст особи». Про тони він не каже нічого,
    отже й міняти їх не має права — інакше один вибір жінки тихо переписував би
    два рішення. Перша гілка розвилки — рівно те, що код цій людині радив би сам
    (`палітра_розвилка.розвилка` сортує statement-гілки в кінець, тож нульова
    ніколи не буває концептом), і вона ж стоїть дефолтом у пулі
    (`міст_пакет`: «гілка приходить уже підставленою, 0 = перша гілка розвилки»).
    Отже вибір «мисматч» міняє РІВНО драбину світлоти й нічого більше.

    Від наміру не залежить: statement-гілки в кінці списку, тож перша законна та
    сама під conventional і під editorial. Цикл, а не `гілки[0]`, — щоб порожня
    чи дивна розвилка впала тут, а не через один кадр у `СХЕМИ[None]`."""
    for g in розвилка(особа, intent=intent)["гілки"]:
        if g["схема"] in СХЕМИ:
            return g["схема"]
    raise ValueError("розвилка не дала жодної схеми з СХЕМИ — мисматчу нема від чого "
                     "брати тони (рівень=%r)" % особа.get("рівень"))



def сторона_біля_обличчя(P, особа, слоти, схема, ролі, S, тони, intent):
    """Обрати, з якого боку від шкіри стоїть річ біля обличчя — ДО побудови драбини.

    `цільове_вікно` віднімає контраст особи від L* шкіри. На темній
    шкірі різниця впирається в підлогу шкали: L*31.6 з контрастом 20.5 дає вікно
    [0,23]. У синьо-фіолетовій дузі на такій світлоті стеля реальних поверхонь
    C*29.6, а поріг, за яким тон перестає читатись нейтраллю, там 34 (виняток
    нейві) — отже роль оголошувалась виродженою, схема переходила на відлуння, і
    КОЛІРНА ВІСЬ ДЛЯ ТЕМНОГО КОЛОРИТУ ЗНИКАЛА ЦІЛКОМ: у фід ішли самі нейтральні
    вікна. Це та сама нерівність, яку знімає R-PC-09, тільки на осі
    світлоти, і вона не була видима жодному тесту, бо «вироджена роль» — законний
    стан системи, а не помилка.

    ЧОМУ ЦЕ НЕ НОВЕ ПРАВИЛО: `колір_образу.цільове_вікно` прямо каже «двобічне: річ може
    бути темнішою або світлішою за обличчя — обидві гілки легітимні». Темніша була
    ЗАШИТА, а не обрана. Темніша лишається першою (на світлій шкірі поведінка не
    міняється — перевірено), світліша пробується ЛИШЕ коли перша не тримає кольору.

    ⚠ ДЕ ЛАМАЄТЬСЯ. Вибір сторони — це вибір ОБРАЗУ («світліше за обличчя» проти
    «темніше»), а тут його робить ГАМУТ. Це законно як ПІДЛОГА (краще світліша
    сторона, ніж жодного кольору), але не як перевага: сторона названа в
    `P["сторона"]`, щоб шар вище міг її перебити нагодою чи бажанням людини.
    Друге обмеження: сторона обирається ОДИН раз, за первинними ролями. Якщо ролі
    перебудуються на відлуння, сторона не переглядається — це видно у виході, а не
    замовчано."""
    приобличчеві = [s for s in слоти
                    if _КОЛІР.SLOT_NEAR_FALLBACK.get(s, 0.2) >= _КОЛІР.NEAR_МІН]
    ролі_дуги = [(ролі[s], тони[ролі[s]]) for s in приобличчеві
                 if тони.get(ролі[s]) not in (None, "нейтраль")]
    if not ролі_дуги:
        return P                      # біля обличчя нема кольорової ролі — нема питання
    if _тримає_колір(P["біля_обличчя"], ролі_дуги, S, intent):
        return P
    if not _тримає_колір(P["світле_біля_обличчя"], ролі_дуги, S, intent):
        return P                      # не тримає жодна — сторона нічого не рятує
    # Мисматч їде далі РАЗОМ із вибором сторони: драбина будується від
    # підставленого контрасту з обох боків, інакше зміна сторони мовчки
    # повертала б вікно до власного контрасту особи.
    P2 = поверхи(особа, слоти, схема, сторона="світліша", мисматч=P.get("мисматч"))
    P2["сторона_чому"] = (
        "темніша сторона приобличчевого вікна %s не тримає кольору в дузі схеми "
        "(стеля реальних поверхонь нижча за поріг, за яким тон читається "
        "нейтраллю) — узято світлішу %s. Обидві сторони легітимні "
        "(колір_образу.цільове_вікно); рішення ухвалене гамутом, не нагодою, тож шар "
        "вище може його перебити" % (P["біля_обличчя"], P2["біля_обличчя"]))
    return P2

def специфікація(F, схема, слоти, якір_тон=None, source="uncontrolled",
                 intent="conventional", фокус=None, принт=None, драп=None, мета="лестити",
                 самозвіт=None, основа=None, дистанція=None):
    """Вихід — фільтр каталогу на кожен слот. Нічого не вирішує про смак:
    схему й якір дає композитор, тут лише арифметика під цю особу.

    якір_тон: кут тону (0–360) або hex речі, від якої будується схема. Якщо не
    заданий — береться тон очей, але ЛИШЕ коли надійність хроми це дозволяє
    (K-PC-05); інакше повертається схема без тонових обмежень і питання людині.

    основа: `вибір_кольору` показу — основа, яку жінка обрала на екрані палітри
    (`база`, `база_hex`, `база_тип`, `насиченість`). Вона НЕ те саме, що `якір_тон`:
    якір задає, де стоять дуги СХЕМИ, а `основа` лишає у виході окреме вікно своєї
    СІМ'Ї (`обрана_основа`), яке `запит_у_фід` кладе в добір нарівні з дугами схеми.
    Два поля, бо дві різні обіцянки: «схема стоїть на цьому тоні» і «ця сім'я мусить
    бути в пулі, навіть коли схема звузилась деінде».

    принт: dict(палітра=<вихід feed.палітра_принту>, слот="сукня") — коли одна річ
    образу принтована. Тоді її внутрішня палітра закриває РОЛІ, сольний слот дістає
    ехо-запит (повтор кольору принту), а гучність принту неперервно піднімає
    перевагу нейтралі в решті слотів.

    `примітки` у поверненому dict — ПОЛЕ ДЛЯ РОЗРОБНИКА, не канал до людини й не
    канал до моделі: поле не має продуктового читача. Воно накопичує
    діагностику специфікації — виродження схеми, невиконанність відлуння,
    утримання тону, гучність принту — і читається оком у пробах. Що ЇДЕ до
    людини й моделі: `слоти` (вікна), `палітра_практична` (через
    `palettes.для_пакета` — кодами й числами), `тон_від_рис`
    і чіпи брифа. Хто захоче показати примітку — мусить це зробити явно, а не
    вважати, що поле вже доїжджає."""
    if схема not in СХЕМИ and схема != МИСМАТЧ:
        raise ValueError(f"невідома схема {схема}; є: {sorted(СХЕМИ)} "
                         f"і модифікатор «{МИСМАТЧ}»")
    особа = O.контраст_особи(F, source)
    if not особа.get("доступно"):
        raise ValueError("нема профілю особи: " + особа.get("чому", ""))
    R = reliability(source)
    # Мисматч — модифікатор драбини, а не шоста схема: він бере тони в першої
    # законної гілки розвилки цієї людини й міняє лише драбину світлоти через
    # `поверхи(мисматч=…)`, не вигадуючи нових дуг.
    мисм, базова = None, схема
    if схема == МИСМАТЧ:
        базова = базова_для_мисматчу(особа, intent)
        # Рівні — від міри рівня особи (як у розвилці), драбина — від фізичного `value_gap`.
        мисм = dict(зсув_мисматчу(max(особа["value_gap"], особа.get("gap_рівня") or 0.0),
                                  драбина=особа["value_gap"]), базова=базова)
    P = поверхи(особа, слоти, базова, мисматч=мисм)
    мисм = P.get("мисматч", мисм)     # `поверхи` дописує вікно образу й виродження
    S = СХЕМИ[базова]

    тон_доступний = R["hue"] >= MIN_TO_EMIT
    if isinstance(якір_тон, str): якір_тон = lch(hx(якір_тон))[2]
    # Якір потрібен завжди: без нього схема з дугами («тональна» = одна сім'я
    # ±12°) перетворюється на «тон вільний», і її пул дорівнює пулу будь-якої
    # схеми. Низька надійність тону з фото записується в
    # `якір_джерело`, а не вимикає схему: жінка бачить, з чого взято дугу, і може
    # обрати базу сама на екрані палітри.
    якір_джерело = "обраний" if якір_тон is not None else None
    if якір_тон is None:
        for _риса in ("очі", "волосся", "шкіра"):
            _р = F.get(_риса) or {}
            if _р.get("h") is not None and (_р.get("C") is None or float(_р.get("C") or 0) >= 8):
                якір_тон = float(_р["h"]) % 360
                якір_джерело = _риса + ("" if тон_доступний else " (надійність тону з фото низька)")
                break
    тони = S["тон"](якір_тон) if якір_тон is not None else {r: None for r in РОЛІ}

    def поле_слота(слот, роль):
        """Вікно для слота будується ПІСЛЯ того, як роль остаточна, щоб слот,
        підвищений до акценту через виродження, не лишився з вікном секунданта
        у смузі, де потрібного кольору не буває."""
        вага = _КОЛІР.SLOT_NEAR_FALLBACK.get(слот, 0.2)
        near = вага >= _КОЛІР.NEAR_МІН
        L = (P["біля_обличчя"] if near else
             P["акцент_L"] if роль == "акцент" else P["секундант_L"])
        # Жорсткість смуги спадає від обличчя рівно за вагою слота:
        # L' = [L0·w, L1 + (100 − L1)·(1 − w)]. При w → 0 світлота вільна, як якірна
        # нейтраль взуття в `палітра_запити.запит_у_фід`, а крок
        # світлоти судить K-COL-01 на ЗІБРАНОМУ образі. Приобличчеві слоти (w ≥
        # `NEAR_МІН`) тримають вікно обличчя K-CLR-02 без зміни. Смуга драбини лишається
        # у полі `L_драбини` — це план кроків, а не фільтр.
        L_драбини = None
        if not near:
            L_драбини = list(L)
            L = [round(L[0] * вага), round(L[1] + (100 - L[1]) * (1 - вага))]
        C_ = list(S["хрома"][роль]); t = тони[роль]
        if near and C_[1] > ГУЧНО and _РЕЄСТР.стриманий_намір(intent):   # K-PER-00
            C_[1] = ГУЧНО - 1
        поле = dict(роль=роль, L=L, C=C_)
        if L_драбини is not None:
            поле["L_драбини"] = L_драбини
        if t == "нейтраль":
            # Визначення нейтралі одне: перевірка йде через `колір_образу.нейтраль`
            # (кемел C*31 і хакі C*19 — нейтралі), а вікно лише окреслює світлоту
            # й стелю найширшого коридору; поріг C*<12 вікно б порожнило.
            поле["сім_я"] = ("нейтраль за коридорами K-COL-06 (ахроматична C*<12, тепла "
                             "h45–115 C*≤34, холодна h230–300 C*≤24); одна сім'я на образ, "
                             "крос лише з кроком ΔL*≥12")
            поле["C"] = [0.0, 34.0]
            поле["тест"] = "колір_образу.нейтраль(lab) is not None"
            # Роль, яку схема тримає нейтральною, передається полем. `дуга_тону` тут не
            # ставиться: її читачі (пул, `тримає_дугу_схеми`, носії тону) чекають дугу-пару,
            # і рядок «нейтраль» там зламав би пул. Суд (`суд_від_моделі.схема_образу`,
            # K-PAL-03 «кольорова річ на нейтральній ролі») читає це поле.
            поле["тон_ролі"] = "нейтраль"
            # Температура нейтралі-якоря рахується тут, а не в розвилці, щоб джерело
            # було одне й прямий виклик специфікація() теж її отримував.
            як = нейтраль_якір(F, source=source, слот=слот, intent=intent,
                               драп=драп, мета=мета, дистанція=дистанція)
            if як.get("придатно") and not як["вільно"]:
                поле["нейтраль_темп"] = як
            поле["сім_я"] = поле["сім_я"] + (
                "; температура: " + як["нота"] if як.get("придатно") else "")
            return поле, False
        if t is None:
            поле["тон"] = "не обмежено: підтон і тон не стверджуються з цього фото (K-PC-05)"
            return поле, False
        поле["дуга_тону"] = t
        # Схема великих поверхонь міряє «чи несе роль колір» межею своїх сімей, а не
        # коридором нейтралі (`палітра_схеми.МЕЖА_СІМ_Ї`).
        зд = здійсненність(L, t, C_, поріг=(МЕЖА_СІМ_Ї if S.get("поверхні") == "великі"
                                            else None)); поле["здійсненність"] = зд
        if зд["ok"]:
            lo = max(C_[0], зд["поріг_нейтралі"] + 2); hi = min(C_[1], round(зд["стеля"]))
            if hi <= lo:      # вікно вивернулось: стеля гамуту нижча за поріг кольору
                поле["C"] = _відступ_хроми(зд, C_)
                поле["попередження"] = (f"вікно вивернулось (C_min {lo} > C_max {hi}): "
                    f"стеля гамуту C*{зд['стеля']} не лишає місця над порогом нейтралі "
                    f"{зд['поріг_нейтралі']} — роль не може бути кольоровою")
                return поле, True
            поле["C"] = [lo, hi]
            return поле, False
        поле["C"] = _відступ_хроми(зд, C_)
        поле["попередження"] = (
            f"на L*{L[0]}–{L[1]} у цій дузі гамут дає максимум C*{зд['стеля']}, "
            f"а щоб не читатись нейтраллю треба C*>{зд['поріг_нейтралі']}: "
            "роль фізично не може нести колір на цій світлоті")
        return поле, True

    ролі = розподіл_ролей(слоти, S)
    P = сторона_біля_обличчя(P, особа, слоти, базова, ролі, S, тони, intent)
    вихід, вироджені = {}, []
    for слот, роль in ролі.items():
        вихід[слот], вирод = поле_слота(слот, роль)
        if вирод: вироджені.append(слот)

    акцентні = [s for s, r in ролі.items() if r == "акцент"]
    примітки = [S["ризик"], P["примітка"]]
    великі = S.get("поверхні") == "великі"
    if вироджені and великі:
        # Схема великих поверхонь не переноситься на аксесуари. Ролі лишаються:
        # слот, який на своїй світлоті кольором бути не може, так і названий, а його
        # сім'ю несуть інші великі речі (`дуги_схеми` нижче кладе її в їхні пули).
        примітки.append(f"{вироджені}: на світлоті цих слотів сім'я їхньої ролі кольором "
                        "бути не може (гамут) — у пулі ці слоти читатимуться нейтраллю; "
                        "колір схеми лишається на інших великих речах, на аксесуари він "
                        "не переноситься")
    elif вироджені:
        примітки.append(f"схема вироджується: {вироджені} не можуть нести колір на своїй "
                        "світлоті (гамут) і читатимуться нейтралями — фактично це "
                        "«нейтрали+акцент», отже акцент потребує другого носія")
        S = dict(S, відлуння=True)
        ролі = розподіл_ролей(слоти, S)
        вироджені = []
        for слот, роль in ролі.items():        # вікна перебудовуються під нові ролі
            вихід[слот], вирод = поле_слота(слот, роль)
            if вирод: вироджені.append(слот)
    # Усі сім'ї схеми входять у пул кожної великої речі.
    # Роль слота — ПЕРША сім'я його пулу, а не єдина. Взірець власниці (оливковий
    # жакет + блакитна сорочка + бордова спідниця) бере жакет і сорочку з ОДНОГО
    # слота «верх» (жакет у каталозі — «верх», а в образі — `шар2`), а в спеку сукні
    # верхнього шару може й не бути (спека, погода). Пул із однією сім'єю на слот не
    # дав би тріади на великих речах ніяк. Поле кожної сім'ї рахує та сама
    # `поле_слота` (світлота — за роллю сім'ї, хрома — її смуга, гамут — межею сімей);
    # сім'я, яка на цій світлоті кольором бути не може, у слот не йде і названа.
    # Три схеми без `поверхні` цього поля не мають зовсім.
    сім_ї_схеми = []
    if великі:
        for _р in РОЛІ:
            _д = тони.get(_р)
            if isinstance(_д, tuple) and all(tuple(x["дуга"]) != _д for x in сім_ї_схеми):
                сім_ї_схеми.append(dict(роль=_р, дуга=list(_д)))
        for _сл in [x for x in вихід if x in ВЕЛИКІ_ПОВЕРХНІ]:
            _своя = tuple(вихід[_сл].get("дуга_тону") or ())
            _дод, _поза = [], []
            for _с in сім_ї_схеми:
                if tuple(_с["дуга"]) == _своя:
                    continue
                _п, _вир = поле_слота(_сл, _с["роль"])
                (_поза if _вир else _дод).append(dict(роль=_с["роль"], дуга=_п["дуга_тону"],
                                                      C=_п["C"], L=_п["L"]))
            if _дод:
                вихід[_сл]["дуги_схеми"] = _дод
            if _поза:
                примітки.append("слот «%s»: сім'я ролі %s на його світлоті кольором бути "
                                "не може (гамут) — у його пул вона не йде"
                                % (_сл, ", ".join(x["роль"] for x in _поза)))
        # ЗРАЗОК СІМ'Ї — середина її вікна на першому слоті, де вона кольором бути може:
        # з нього рядок жінці бере слово крамниці (`палітра_схеми.слово_сім_ї`).
        import math as _м_з
        for _с in сім_ї_схеми:
            _поля = [v for v in вихід.values() if v.get("роль") == _с["роль"]
                     and v.get("дуга_тону") and not v.get("попередження")]
            _поля += [д for v in вихід.values() for д in (v.get("дуги_схеми") or ())
                      if д["роль"] == _с["роль"]]
            if not _поля:
                continue
            _п = _поля[0]
            _L_з, _C_з = sum(_п["L"]) / 2.0, sum(_п["C"]) / 2.0
            _lo, _hi = float(_с["дуга"][0]), float(_с["дуга"][1])
            _h_з = _м_з.radians((_lo + ((_hi - _lo) % 360) / 2.0) % 360)
            _с["зразок"] = _cs_з.hex_з_lab((_L_з, _C_з * _м_з.cos(_h_з), _C_з * _м_з.sin(_h_з)))
    # ── ТЕМПЕРАТУРА НЕЙТРАЛІ-ЯКОРЯ: РАХУЄТЬСЯ ДЛЯ ЯКІРНОГО СЛОТА ЗАВЖДИ ────────
    # `нейтраль_темп` вище ставиться ЛИШЕ в гілці `t == "нейтраль"` — тобто там, де
    # СХЕМА дала слотові нейтральний тон. Слоти-якорі («взуття», «сумка», «пояс»,
    # «колготи») дістають від схеми КОЛЬОРОВУ роль майже завжди — і саме тому
    # `запит_у_фід` додає їм окремий нейтральний рядок. Тому вікно рахує та сама
    # `нейтраль_якір` на тих самих F/source/intent/драп/мета і кладе його в ОКРЕМЕ
    # поле. Ім'я окреме свідомо: `нейтраль_темп` означає
    # «слот сам по собі нейтральний за схемою», `якір_нейтраль_темп` — «слотові
    # додається запасний нейтральний рядок, ось його температура».
    # `вільно=True` поля НЕ дістає: для далеких слотів («взуття» near 0.00,
    # «колготи» 0.00) вага вікна нульова, b-межі вироджуються в увесь простір
    # нейтралей, і таке «вікно» було б безмежним твердженням замість обмеження.
    for _слот_якір in ЯКІРНІ_СЛОТИ:
        if _слот_якір not in вихід: continue
        як = нейтраль_якір(F, source=source, слот=_слот_якір, intent=intent,
                           драп=драп, мета=мета, дистанція=дистанція)
        if як.get("придатно") and not як["вільно"]:
            вихід[_слот_якір]["якір_нейтраль_темп"] = як
    акцентні = [s for s, r in ролі.items() if r == "акцент"]
    потребує_фокус = (S["відлуння"] and len(акцентні) < 2
                      and not (фокус and set(акцентні) & set(фокус)))
    if потребує_фокус:
        # Сила K-COL-05 — `default`, не `hard`, тож
        # `колір_образу.відлуння` віддає його РЕПЛІКОЮ, і образ проходить.
        примітки.append(f"НЕВИКОНАННО як є: схема тримається на відлунні, а носіїв "
                        f"акценту {len(акцентні)}. Додати другий носій ({', '.join(НОСІЇ_АКЦЕНТУ[:4])}) "
                        f"або оголосити {акцентні or 'акцентний слот'} фокусною зоною — "
                        "інакше колір_образу.відлуння віддасть K-COL-05 реплікою (регістр "
                        "«репліка», не блокує): образ пройде, але з великим неперервним "
                        "штрафом і запитом другого носія в каталог")
    if not тон_доступний:
        примітки.append("тон і підтон загейтовані джерелом: питати людину про метали "
                        "й білі, працювати у value-термінах")
    # Палітра принту доходить до композитора.
    принт_вихід = None
    if принт and принт.get("палітра"):
        рп = роль_принту(принт["палітра"], list(вихід), принт.get("слот"), intent)
        принт_вихід = рп
        сл_принту = принт.get("слот")
        if сл_принту in вихід:
            вихід[сл_принту]["несе_принт"] = dict(закриває=рп["закриває"],
                                                  гучність=рп["гучність"])
        q = рп.get("запит_ехо")
        if q and q["слот"] in вихід:
            # ехо не перезаписує поле слота, а лягає поруч: рішення несе `сила`
            вихід[q["слот"]]["принт_ехо"] = q
        # гучність принту неперервно піднімає перевагу нейтралі в РЕШТІ слотів
        for сл, в in вихід.items():
            if сл != сл_принту:
                в["нейтраль_перевага"] = рп["нейтраль_перевага"]
        примітки.append(
            "принт у слоті %s закриває %s; ехо-акцент → %s (сила %.2f); "
            "нейтраль-перевага решти слотів %.2f" % (
                сл_принту, рп["закриває"] or "—",
                (q["слот"] if q else "нема куди"), (q["сила"] if q else 0.0),
                рп["нейтраль_перевага"]))

    # ── ТОН ВІД РИС: друга, незалежна від якоря-схеми тонова вісь ─────────────
    # Вихід НЕСЕ, яка вісь звідки і що зняло б утримання, щоб мовчання тону не
    # змішувалося зі станом «пораховано й вийшло широко» в одному порожньому полі.
    тв = тон_від_рис(F, базова, source, intent)   # відношення бере БАЗОВА схема: тонів мисматч не міняє
    # Персональна палітра — зона в LCh від рис, з ролями й рангами. Це окремий об'єкт:
    # її читає бриф (personal_palette.словами) і запит_у_фід (рядки з рангом риси).
    палітра_особи = _PP.палітра(F, source=source)
    # Практиковий шар палітр: позиція на трьох осях →
    # палітра, що поділяє домінанту людини (Sci\ART/Kalisz, Lamport, JPCA), конкретні
    # кольори з назвами, прийоми як оператори. Контраст особи — той самий, що в розвилці.
    # Без шкіри чи волосся `контраст_особи` повертає
    # `доступно=False` без винятку — `.get("рівень")` дає None і без обгортки.
    # Виняток звідти — зіпсований профіль (риса без `L`), і він летить у
    # `bridge.виклик` (`помилка` + `код`), а не стає «контраст невідомий».
    _рівень = O.контраст_особи(F, source=source).get("рівень")
    # Самозвіт мусить доходити до практикової палітри, щоб `bridge._основи` і
    # картка брифа відповідали про метал за одним входом.
    палітра_практична = _PL.палітра_практична(F, source=source, самозвіт=самозвіт,
                                              контраст_рівень=_рівень, intent=intent)
    if тв["придатно"]:
        живі = [nm for nm, d in тв["риси"].items() if d.get("дуги")]
        німі = [nm for nm, d in тв["риси"].items() if not d.get("дуги")]
        примітки.append(
            "тон від рис: голосують %s%s; перегуків %d, напруг %d. Риси НЕ "
            "усереднюються — кожна дає власний рядок запиту"
            % (", ".join(живі) or "жодна",
               (" (мовчать: %s — ахроматичні)" % ", ".join(німі)) if німі else "",
               len(тв["перегуки"]), len(тв["напруги"])))
    else:
        примітки.append("тон від рис УТРИМАНО (%s): %s. Зняло б: %s"
                        % (тв["утримано"]["правило"], тв["утримано"]["чому"],
                           тв["утримано"]["що_зняло_б"]))

    # Обрана основа потребує вікна її сім'ї, а не лише речення в пакеті. Тут є дві
    # різні дії: `якір_тон` зсуває дуги СХЕМИ на обраний тон, а тут рахується вікно
    # сім'ї самої основи, з її власною хромою. Воно
    # потрібне окремо, бо дуга схеми — це ±20° навколо якоря, а сім'я практиків
    # ширша (червона тепла 15–45°), і саме нею людина називає свій колір.
    # ХРОМА БЕРЕТЬСЯ З САМОЇ ОСНОВИ, А НЕ З МНОЖНИКА. Смуга гами
    # («приглушені / середні / насичені») уже ВБУДОВАНА в hex основи:
    # `bridge._ґратка_основ` генерує клітинку на хромі своєї смуги, і показ
    # фільтрує ряд саме за нею. Тому центр вікна — C* обраного hex, а півширина —
    # половина смуги хроми, яку схема просить у цього слота. Множити ще й на
    # `brief.НАСИЧЕНІСТЬ` означало б порахувати вибір смуги двічі.
    обрана_основа = None
    if isinstance(основа, dict) and основа.get("база_hex") and основа.get("база_тип") == "колір":
        # `база_hex` — клітинка ґратки основ, яку породив
        # `bridge._ґратка_основ` і яку жінка лише обрала; нечитний hex тут — збій
        # показу чи мосту, і він летить у `bridge.виклик` (`помилка` + `код`), а
        # не тихо знімає вікно обраної основи з пулу.
        _L_о, _C_о, _h_о = lch(hx(основа["база_hex"]))
        _сім = _PL.сім_я_тону(_h_о)
        обрана_основа = dict(
            база=основа.get("база"), hex=основа["база_hex"],
            насиченість=основа.get("насиченість"),
            L=round(_L_о, 1), C=round(_C_о, 1), h=round(_h_о, 1),
            сім_я=(_сім[0] if _сім else None), версія=(_сім[1] if _сім else None),
            дуга=(_сім[2] if _сім else _дуга(_h_о, 20)),
            # смуга світлоти клітинки основи — від мосту (`міст_основи.смуга_L_основи`):
            # рядок домінанти в цій смузі кладе `запит_у_фід`
            смуга_L=основа.get("смуга_L"),
            джерело=("сім'я «%s» (%s) за `palettes.СІМ_Ї`" % (_сім[0], _сім[1])
                     if _сім else "дуга ±20° навколо обраного тону: кут поза дугами сімей"))
    вих = dict(обрана_основа=обрана_основа,
                бік_b=бік_b_проти_людини(F),      # R-COL-16: ключ носія для рядків у фід
                якір_джерело=якір_джерело, схема=схема, потребує_фокус=потребує_фокус, вироджені_ролі=вироджені or None, якір_тон=(round(якір_тон, 1) if якір_тон is not None else None),
                принт=принт_вихід, тон_від_рис=тв, палітра=палітра_особи,
                # П-5, аудит/ПРОДУКТ.md п.12: факти палітри їдуть кодами й числами
                # з `palettes.для_пакета` (`axes`, `window`,
                # `accent_families`, `neutral_axes`, `wardrobe_season`, `calibration`).
                # `палітра_словами` (палітра особи) читача не мала ні одного.
                палітра_практична=палітра_практична,
                намір=intent, контраст_особи=особа["value_gap"],
                # важіль K-CLR-03 їде назовні: бриф називає його жінці, проба звіряє з рангом
                ліміт_біля_обличчя=P.get("ліміт_біля_обличчя"), важіль_макіяжу=P.get("важіль_макіяжу"),
                слоти=вихід, примітки=примітки,
                статус="усі межі T3, не калібровані; вихід придатний як фільтр фіду, "
                       "не як обіцянка, що така річ у каталозі є")
    if великі:
        # Які сім'ї схема обіцяє і де, читають добір (`запит_у_фід`,
        # `міст_пакет`) і суд (`палітра_схеми.обіцянка_схеми`) — один перелік на обидва боки,
        # інакше генератор і перевіряльник знову мали б два різні «кольори схеми».
        # Сім'я, у чиїй дузі лежить обрана основа, зветься словом самої жінки
        # («оливковий»), а не словом лексикону для зразка («пісочний»).
        if обрана_основа and обрана_основа.get("база"):
            for _с in сім_ї_схеми:
                if сім_я_схеми(hx(обрана_основа["hex"]), [_с]):
                    _с["слово"] = str(обрана_основа["база"]).split("·")[0]
        вих["поверхні"] = "великі"
        вих["сім_ї_схеми"] = сім_ї_схеми
    if мисм:
        # ДВА ПОЛЯ, БО ДВІ РІЗНІ ОБІЦЯНКИ. `схема` — те, що ОБРАЛА жінка (це ім'я
        # стоїть у ключі пулу й на чипі); `базова_схема` — звідки взяті дуги тону.
        # Злити їх означало б або сховати її вибір, або збрехати про походження дуг.
        вих["базова_схема"] = базова
        вих["мисматч"] = мисм
    return вих

def розвилка_специфікацій(F, слоти, source="uncontrolled", intent="conventional",
                          якір_тон=None, фокус=None, драп=None, мета="лестити",
                          самозвіт=None, дистанція=None, явні=()):
    """ГОЛОВНИЙ вхід замість `специфікація` для одного вибору: віддає РОЗВИЛКУ
    каталожних фільтрів — по одному на кожну законну схему цього колориту, з вагою
    згоди. Retrieval тягне гарнітури під КОЖНУ гілку; фінальну палітру обирає людина.

    Гілки, що мапляться на реальну схему в СХЕМИ, отримують повну специфікацію +
    плаский запит у фід. «Контраст-мисматч» теж бере
    тони в базової схеми і міняє драбину світлоти (`специфікація` → `поверхи`), тож
    вікна в нього СВОЇ й фабрикувати нічого не треба. Приобличчеве вікно при цьому
    не послаблюється — воно лишається таким самим вузьким, лише стоїть на
    підставленому контрасті; ліміт K-CLR-02 у виході далі власний, і суд міряє
    проти нього. Схема, якої нема ні в СХЕМИ, ні серед модифікаторів, і далі
    проходить як позначена опція зі `статус_гілки`, а не як фейковий запит (правило 6).

    `явні` — схеми, названі поіменно тим, хто кличе (вибір жінки на екрані
    палітри). Їдуть у `розвилка` без змін: гейт наміру й далі вирішує, що код
    радить сам, але не скасовує названого прохання."""
    особа = O.контраст_особи(F, source)
    if not особа.get("доступно"):
        raise ValueError("нема профілю особи: " + особа.get("чому", ""))
    R = розвилка(особа, intent=intent, явні=явні)
    # Одне питання має одну відповідь у межах виходу: і `температура`, і палітра
    # в гілках мусять рахуватися з тим самим самозвітом.
    темп = температура(F, source, intent, самозвіт=самозвіт)

    гілки_out = []
    for g in R["гілки"]:
        рядок = dict(g)   # копія: схема, вага, коли, застереження, [хрома_акценту]
        if g["схема"] in СХЕМИ or g["схема"] == МИСМАТЧ:
            спец = специфікація(F, g["схема"], слоти, якір_тон=якір_тон,
                                source=source, intent=intent, фокус=фокус,
                                драп=драп, мета=мета, самозвіт=самозвіт,
                                дистанція=дистанція)
            рядок["спец"] = спец
            зфід = запит_у_фід(спец)
            # Температура впорскується неперервно й послотно: кожен нейтральний
            # рядок дістає вікно b* за власним near і силу переваги, за якою retrieval
            # може відступати. Вікно приходить зі специфікації через `запит_у_фід`,
            # щоб його не рахували у двох місцях.
            рядок["запит_у_фід"] = зфід
            рядок["потребує_фокус"] = спец["потребує_фокус"]
            рядок["вироджені_ролі"] = спец["вироджені_ролі"]
            if спец.get("мисматч"):      # чиї тони й на скільки зсунуто — назовні, не в примітку
                рядок["базова_схема"] = спец["базова_схема"]
                рядок["мисматч"] = спец["мисматч"]
            # цільові частки площ по слотах — з дефолтної (градуйованої) стратегії пропорції.
            # Це ОРІЄНТИР для композитора (акцент має бути на малому слоті), не гейт;
            # забезпечення частки — на боці суд_образу.review, де є площі (K-COL-07 поки не реалізовано).
            за_замовч = next(s for s in g["пропорція"]["стратегії"]
                             if s["назва"] == g["пропорція"]["за_замовчуванням"])
            # У схемі великих поверхонь частку площі мають лише великі речі —
            # сумка чи взуття тут лише відлунюють, і «акцент 20–40 %» на них був би неправдою.
            _лише_великі = спец.get("поверхні") == "великі"
            рядок["цільові_частки_площ"] = {
                слот: (None if _лише_великі and слот not in ВЕЛИКІ_ПОВЕРХНІ
                       else за_замовч["частки"].get(поле.get("роль")))
                for слот, поле in спец["слоти"].items()}
            рядок["частки_статус"] = ("орієнтир, не гейт; конвергентне ядро — 'акцент найменший', "
                                      "числа запозичені (T3); перевірка частки — на боці review")
        else:
            рядок["спец"] = None
            рядок["запит_у_фід"] = None
            рядок["статус_гілки"] = "unknown_scheme"
        гілки_out.append(рядок)

    return dict(контраст_рівень=R["контраст_рівень"], value_gap=R["value_gap"],
                ясність=R["ясність"], intent=intent, температура=темп,
                розвилка=гілки_out, вісь_розходження=R["вісь_розходження"],
                згоди_нема=R["згоди_нема"], провенанс=R["провенанс"],
                примітка="це РОЗПОДІЛ, не вибір: кожна гілка — законна палітра з вагою згоди. "
                         "Модуль не звужує до однієї; звуження — це або людина, або композитор "
                         "під конкретну нагоду. Ваги порядкові, не калібровані. Температура "
                         "множиться на схему/контраст/пропорцію, не конкурує з ними.")
