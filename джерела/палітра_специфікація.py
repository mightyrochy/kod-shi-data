def поверхи(особа, _слоти, _схема, сторона="темніша", мисматч=None):
    """Розкладка L* по ролях. Головне обмеження — асиметричне:
    біля обличчя вікно вузьке (K-CLR-02), а кроки світлоти (K-COL-01) мусять
    десь бути. Отже кроки йдуть у низ і взуття — і це не хитрість, а те саме,
    що корпус каже прямо: «низ і взуття майже вільні».

    `сторона` — з якого боку від шкіри стоїть річ біля обличчя; легітимні обидві
    сторони, як задає `колір_образу.цільове_вікно`. Це параметр саме тут, а не нижче
    по течії, бо від приобличчевого вікна рахується вся драбина світлоти
    (секундант, акцент, низ). Зміна сторони лише в `поле_слота`, після побудови
    драбини, може вкласти акцент усередину приобличчевого вікна й порушити K-COL-01.

    `_слоти` і `_схема` НЕ ЧИТАЮТЬСЯ СВІДОМО: трійка (особа, слоти, схема) — одна на
    обидві приобличчеві функції (`_сторона_біля_обличчя` читає всі три), а драбина
    світлоти стоїть на РОЛЯХ (їх три, і вони не залежать ні від переліку слотів, ні
    від відношення тону), тому тут працює лише особа.

    `мисматч` — вихід `палітра_схеми.зсув_мисматчу` (плюс `базова`), коли жінка
    обрала гілку «контраст-мисматч». ТОДІ І ЛИШЕ ТОДІ драбина рахується не від
    власного `value_gap`, а від підставленого: це і є вся реалізація мисматчу, і
    вона стоїть РІВНО ТУТ, бо тут — єдине місце, де контраст особи перетворюється
    на світлоту образу. Що при цьому НЕ міняється, і це не дрібниця:
      · вікно лишається ТАКИМ САМИМ ВУЗЬКИМ — рахує його та сама `цільове_вікно`
        з тими самими `under`/`over`; мисматч рухає вікно, а не розтягує (K-CLR-02
        не послаблено: суд і далі міряє стрибок проти ВЛАСНОГО контрасту особи, і
        `ліміт_біля_обличчя` нижче лишається її власним);
      · важіль помади додається так само й від тієї самої функції (K-CLR-03);
      · кроки між поверхами далі стоять на `КРОК` (K-COL-01) — арифметика драбини
        нижче не чіпається жодним множником.
    Коли шкала світлоти впирається в край (0 або 100) і вікно стає вужчим за один
    розрізнюваний крок, це НАЗИВАЄТЬСЯ в `мисматч["вироджено"]`, а не мовчить."""
    L_шк = особа["L_шкіри"]; gap = особа["value_gap"]
    # Драбина міряється від підставленого контрасту лише під обраним мисматчем;
    # без нього `gap_драбини is gap` — жодного множника, жодної зміни арифметики.
    _мис = dict(мисматч) if мисматч else None
    gap_драбини = float(_мис.get("драбина", _мис["підставлений"])) if _мис else gap
    # Важіль макіяжу має бути той самий, що в ранзі основ і в суді (K-CLR-03):
    # він піднімає стелю вікна, не рухаючи ближнього краю.
    ліміт_обл, важіль_мк = _KC.дозволений_контраст(особа)
    Δ_мк = float(важіль_мк["Δ"]) if важіль_мк else 0.0
    темне = _КОЛІР.цільове_вікно(L_шк, gap_драбини, темніша=True, важіль=Δ_мк)
    світле = _КОЛІР.цільове_вікно(L_шк, gap_драбини, темніша=False, важіль=Δ_мк)
    вікно_обличчя = світле if сторона == "світліша" else темне
    _розсунуто = вікно_обличчя[1] - вікно_обличчя[0] < 6
    if _розсунуто:                                   # особа з екстремальним контрастом
        вікно_обличчя = [max(0, вікно_обличчя[0]-6), min(100, вікно_обличчя[1]+6)]
    if _мис is not None:
        # НАЗВАНА ПРИЧИНА ЗАМІСТЬ ПОРОЖНЕЧІ. Підставлений контраст може винести
        # вікно за край шкали (темна шкіра + висококонтрастна драбина): вікно
        # лишається законним, але вужчим за крок, і пул під ним — вужчий. Це
        # факт про ШКАЛУ, не про схему, тож він їде полем, а не мовчанням.
        _ш = вікно_обличчя[1] - вікно_обличчя[0]
        _мис["вікно_образу"] = list(вікно_обличчя)
        _мис["ширина_вікна"] = round(_ш, 1)
        if _розсунуто:
            _мис["вироджено"] = ("вікно біля обличчя зійшлося (менше за 6 L*) і його "
                                 "розсунуто на ±6 — на цій шкалі підставлений контраст "
                                 "%.1f L* не вміщається" % gap_драбини)
        elif _ш < КРОК:
            _мис["вироджено"] = ("вікно біля обличчя звузилось до %.0f L* (менше за крок "
                                 "світлоти %.0f): шкала вперлась у край, пул під цією "
                                 "драбиною вужчий, ніж під матчем" % (_ш, КРОК))
    база = sum(вікно_обличчя)/2
    низ_вниз = [max(2, round(база - 2*КРОК - 8)), max(8, round(база - КРОК))]
    низ_вгору = [min(92, round(база + КРОК)), min(98, round(база + 2*КРОК + 8))]
    # низ веде в той бік, де більше місця в шкалі
    низ = низ_вниз if (база - 0) > (100 - база) else низ_вгору
    # Ролі далеко від обличчя мусять мати РІЗНІ поверхи, інакше буквальне виконання
    # специфікації дає низ, взуття й сумку на одній світлоті:
    # формально 2 кроки, фактично секундант і акцент нерозрізнимі.
    ширина = низ[1] - низ[0]
    секундант = [низ[0], round(низ[0] + ширина*0.45)]
    акцент = [round(низ[0] + ширина*0.55 + КРОК*0.5), min(96, низ[1] + round(КРОК))]
    P = dict(біля_обличчя=вікно_обличчя, світле_біля_обличчя=світле,
             темне_біля_обличчя=темне, сторона=сторона,
             далеко_від_обличчя=низ, секундант_L=секундант, акцент_L=акцент,
             ліміт_біля_обличчя=round(ліміт_обл, 1), важіль_макіяжу=важіль_мк,
             примітка="кроки світлоти виносяться від обличчя: біля лиця вікно задає "
                      "контраст особи, і рухати його не можна без штрафу K-CLR-02"
                      + (" (стелю вікна піднято на %.0f L* помітним макіяжем, K-CLR-03)" % Δ_мк
                         if важіль_мк else ""))
    if _мис is not None:
        # Поле додається ЛИШЕ під мисматчем: без нього вихід байт у байт той самий,
        # що був, — і знімок стенда це й показує.
        P["мисматч"] = _мис
        P["примітка"] = (P["примітка"] + ". ОБРАНИЙ МИСМАТЧ: драбина рахується від "
                         "%.1f L* замість власних %.1f L* особи (%s → %s); ліміт біля "
                         "обличчя лишається власним — суд K-CLR-02 міряє проти нього й "
                         "назве цей розрив задумом, а не дефектом"
                         % (_мис.get("драбина", _мис["підставлений"]),
                            _мис.get("драбина_власна", _мис["власний"]),
                            _мис["рівень_власний"], _мис["рівень_образу"]))
    return P

