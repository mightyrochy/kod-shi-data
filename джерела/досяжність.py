"""ДОСЯЖНІСТЬ: яку функцію продукту виконує ЖИВИЙ ШЛЯХ, а яку — ніхто.

ЧОМУ ЦЕЙ ФАЙЛ Є (розділ 3 підсумку, наряд Н-00-03). Про кожен великий модуль у
цьому дереві питання «це ще працює чи вже мертве» вирішувалось грепом і
пам'яттю. Грепом видно ЗГАДКУ, а не ВИКОНАННЯ: `extract` згадано в шести
файлах і не виконується жодного разу; `composer._портфель` живе під `вимір=N`,
якого жоден живий виклик не подає. Обидва висновки зроблено окремими пробами,
кожну з яких після використання викинули. Тут лишається механізм.

ЩО ЦЕ МІРЯЄ. Рівно три числа на модуль: скільки функцій у ньому ОГОЛОШЕНО (AST),
скільки з них ВИКОНАВ живий шлях (`sys.setprofile` над `тест_живого_шляху.main`
— той самий сценарій шести викликів моста × дві гілки × три наміри, який
оголошено в Н-00-02), і скільки лишилось невиконаними. Далі кожна невиконана
функція проходить грепом по дереву (.py/.js/.html) і дістає МІТКУ — хто її
взагалі згадує.

МІТОК ЧОТИРИ, А НЕ ТРИ, І ЦЕ ВИМІР, А НЕ СВАВІЛЛЯ. Наряд називає три —
«прилад/тест/ніхто». Вони мовчки припускають, що функцію, яку кличе продукт,
живий шлях ВИКОНАЄ. Це неправда: виклик стоїть за гілкою, якої батарея не
взяла (інший намір, інша нагода, порожній `спец_слоти`). Таких функцій тут
сотні, і зарахувати їх у «ніхто» означало б віддати наряду Н-02-03 список на
знесення, до якого входить живий код, — рівно та підміна «мій стенд його не
викликав» → «воно мертве», проти якої написано `gate_reach.прогін_зібраного`.
Тому:
  · `продукт` — згадана у ЖИВОМУ модулі (або в `показ.html`/`worker.js`, які
    кличуть Python РЯДКОМ через Pyodide). Не виконана — значить, гілка;
  · `тест`    — лише гейти й проби;
  · `прилад`  — лише вимірювачі (`прилади.прилад`);
  · `ніхто`   — ніде, крім власного `def`. ОЦЕ і є вхід для Н-02-03.

ЧОГО ЦЕ НЕ ДОВОДИТЬ (та сама межа, що в решті приладів):
  · «виконано» не означає «правильно». Профайлер бачить виклик, не вердикт;
  · «не виконано» не означає «мертве» — див. мітки вище. Мертве тут називається
    одним словом і тільки одним: `ніхто`;
  · батарея одна. Розширення сценарію зменшить «не виконано» і не зменшить
    «ніхто»: «ніхто» — це греп по дереву, а не прогін.

ЦІНА НАЗВАНА. `sys.setprofile` дорожчий за прогін без нього (подія на кожен
виклик), і весь прилад коштує рівно один живий прогін плюс скан теки. Приймання
наряду — «файл породжується за < 10 хв»; час прогону друкується останнім рядком,
щоб деградацію було видно, а не вгадувано.

Прогін:  python3 досяжність.py                 (пише аудит/ДОСЯЖНІСТЬ.md)
         python3 досяжність.py --без-прогону   (лише статика: оголошення й мітки)
         python3 досяжність.py --md ФАЙЛ
"""
