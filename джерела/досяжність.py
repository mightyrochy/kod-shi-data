def модулі(корінь=None):
    """Живі модулі теки: усе, що .py і не прилад. Критерій один — `прилади`."""
    корінь = корінь or ТУТ
    return [f[:-3] for f in sorted(os.listdir(корінь))
            if f.endswith(".py") and not _прилади.прилад(f)]


def рід_файла(шлях):
    """`тест` / `прилад` / `продукт`. Тест перевіряється першим — див. вище."""
    імя = os.path.basename(шлях)
    if імя.startswith(ТЕСТИ_ПРЕФІКС) or імя in ТЕСТИ_ІМЕНА:
        return "тест"
    if імя.endswith(".py") and _прилади.прилад(імя):
        return "прилад"
    return "продукт"


# ── 1. ЩО ОГОЛОШЕНО (AST) ────────────────────────────────────────────────────
def _шукати(імя, префікс):
    """Яке ІМ'Я грепати за цю функцію. Зазвичай — власне, але не завжди.

    Дандер (`__init__`, `__iter__`) не кличуть на ім'я: його кличе інтерпретатор
    через КЛАС. Грепнувши `__init__`, прилад оголосив би конструктор кожного
    класу мертвим — і віддав би цей список наряду Н-02-03 на знесення. Тому за
    дандер грепається ім'я класу, у якому він оголошений.
    """
    if імя.startswith("__") and імя.endswith("__") and префікс.endswith("."):
        клас = префікс[:-1].split(".")[-1]
        if клас and not клас.endswith(">"):
            return клас
    return імя


def _обійти(вузли, префікс, вих):
    """Повне ім'я функції рівно так, як його будує CPython у `co_qualname`.

    Без `<locals>` вкладена функція злилася б з однойменною модульною, і дві
    різні функції рахувались би за одну. Це не теорія: `_проф`, `tracer`,
    `імп` — вкладені імена, що трапляються в дереві не раз.
    """
    for в in вузли:
        if isinstance(в, (ast.FunctionDef, ast.AsyncFunctionDef)):
            повне = префікс + в.name
            вих.append(dict(повне=повне, імя=в.name, рядок=в.lineno,
                            шукати=_шукати(в.name, префікс),
                            приватна=в.name.startswith("_"),
                            вкладена="<locals>" in повне or "." in префікс))
            _обійти(в.body, повне + ".<locals>.", вих)
        elif isinstance(в, ast.ClassDef):
            _обійти(в.body, префікс + в.name + ".", вих)
        else:
            for поле in ("body", "orelse", "finalbody"):
                _обійти(getattr(в, поле, []) or [], префікс, вих)
            for h in getattr(в, "handlers", []) or []:
                _обійти(h.body, префікс, вих)


def оголошені(корінь=None):
    """{модуль: [{повне, імя, рядок, приватна, вкладена}]} по всіх живих .py."""
    корінь = корінь or ТУТ
    вих = {}
    for м in модулі(корінь):
        шлях = os.path.join(корінь, м + ".py")
        try:
            дерево = ast.parse(io.open(шлях, encoding="utf-8").read(), filename=шлях)
        except SyntaxError as e:
            print("  ⚠ %s не розбирається: %s" % (м, e))
            continue
        сп = []
        _обійти(дерево.body, "", сп)
        вих[м] = сп
    return вих


# ── 2. ЩО ВИКОНАВ ЖИВИЙ ШЛЯХ ─────────────────────────────────────────────────
def виконані(корінь=None, аргументи=None):
    """({(модуль, повне_ім'я): викликів}, код_виходу_сценарію, секунди).

    Сценарій — `тест_живого_шляху.main`, тобто рівно те, що оголошено живим
    шляхом у Н-00-02, а не власна вигадана батарея. Другий сценарій тут був би
    другим визначенням «живого», і два визначення розійшлись би на першій же
    правці — саме те, від чого лікується `прилади.py`.
    """
    корінь = корінь or ТУТ
    файли = {}
    for м in модулі(корінь):
        ш = os.path.join(корінь, м + ".py")
        файли[ш] = м
        файли[os.path.realpath(ш)] = м
    лічба = collections.Counter()

    def _проф(кадр, подія, арг):
        if подія == "call":
            к = кадр.f_code
            м = файли.get(к.co_filename)
            if м is not None:
                лічба[(м, к.co_qualname)] += 1

    import тест_живого_шляху as ЖШ
    почато = time.time()
    sys.setprofile(_проф)
    try:
        rc = ЖШ.main(аргументи if аргументи is not None else [])
    finally:
        sys.setprofile(None)
    return лічба, rc, time.time() - почато


# ── 3. ХТО ЦЕ ВЗАГАЛІ ЗГАДУЄ (греп по дереву) ────────────────────────────────
def _дерево_файлів(корінь=None):
    """[(шлях, рід, рядки)] — .py/.js/.html усього репозиторію, крім породженого."""
    корінь = корінь or КОРІНЬ
    вих = []
    for тека, підтеки, файли in os.walk(корінь):
        підтеки[:] = [д for д in підтеки if д not in (".git", "__pycache__", "node_modules")]
        for f in sorted(файли):
            if not f.endswith(РОЗШИРЕННЯ):
                continue
            if f in ПОРОДЖЕНІ or _ЗІБРАНИЙ.match(f):
                continue
            ш = os.path.join(тека, f)
            try:
                if os.path.getsize(ш) > МЕЖА_ФАЙЛА:
                    continue
                рядки = io.open(ш, encoding="utf-8", errors="replace").read().splitlines()
            except OSError:
                continue
            вих.append((ш, рід_файла(ш), рядки))
    return вих


_КОМЕНТАР = re.compile(r"^\s*(#|//|\*)")
_ОЗНАЧЕННЯ = re.compile(r"^\s*(?:async\s+)?def\s+")


def мітки(імена, корінь=None, дерево=None):
    """{ім'я: (мітка, [файли])}. Мітка — найсильніша зі знайдених згадок.

    Згадкою НЕ вважається рядок власного `def` і рядок-коментар: перше зробило б
    кожну функцію «згаданою» самою собою, друге піднімало б мітку описом того,
    що функція мертва. Обидва випадки в цьому дереві реальні.
    """
    дерево = дерево if дерево is not None else _дерево_файлів(корінь)
    імена = sorted(set(імена))
    if not імена:
        return {}
    рег = {і: re.compile(r"(?<![\w])%s(?![\w])" % re.escape(і)) for і in імена}
    знайдено = {і: collections.defaultdict(set) for і in імена}
    for ш, рід, рядки in дерево:
        for рядок in рядки:
            if _КОМЕНТАР.match(рядок) or _ОЗНАЧЕННЯ.match(рядок):
                continue
            for і in імена:
                if і in рядок and рег[і].search(рядок):
                    знайдено[і][рід].add(os.path.relpath(ш, КОРІНЬ))
    вих = {}
    for і in імена:
        де = знайдено[і]
        for м in МІТКИ[:-1]:
            if де.get(м):
                вих[і] = (м, sorted(де[м]))
                break
        else:
            вих[і] = ("ніхто", [])
    return вих


# ── 4. ЗВЕДЕННЯ ──────────────────────────────────────────────────────────────
def зібрати(корінь=None, прогін=True, аргументи=None):
    """(рядки_модулів, невиконані, службове). Один прохід, усе інше — друк."""
    корінь = корінь or ТУТ
    ого = оголошені(корінь)
    if прогін:
        лічба, rc, секунди = виконані(корінь, аргументи)
    else:
        лічба, rc, секунди = collections.Counter(), None, 0.0
    вик = set(лічба)

    невиконані = []
    for м in sorted(ого):
        for f in ого[м]:
            if (м, f["повне"]) not in вик:
                невиконані.append(dict(f, модуль=м))
    мт = мітки({f["шукати"] for f in невиконані}, корінь)
    for f in невиконані:
        f["мітка"], f["де"] = мт.get(f["шукати"], ("ніхто", []))

    рядки = []
    for м in sorted(ого):
        усього = len(ого[м])
        зроблено = sum(1 for f in ого[м] if (м, f["повне"]) in вик)
        свої = [f for f in невиконані if f["модуль"] == м]
        c = collections.Counter(f["мітка"] for f in свої)
        рядки.append(dict(модуль=м, усього=усього, виконано=зроблено,
                          не_виконано=усього - зроблено,
                          викликів=sum(n for (мм, _), n in лічба.items() if мм == м),
                          **{к: c.get(к, 0) for к in МІТКИ}))
    службове = dict(rc=rc, секунди=секунди, прогін=прогін,
                    модулів=len(ого), функцій=sum(len(v) for v in ого.values()),
                    викликів=sum(лічба.values()))
    return рядки, невиконані, службове


def друк(рядки, невиконані, службове):
    усього = sum(r["усього"] for r in рядки)
    вик = sum(r["виконано"] for r in рядки)
    c = collections.Counter(f["мітка"] for f in невиконані)
    print("=" * 78)
    print("ДОСЯЖНІСТЬ: %d живих модулів · %d функцій · виконав живий шлях %d (%.0f %%)"
          % (службове["модулів"], усього, вик, 100.0 * вик / max(1, усього)))
    if not службове["прогін"]:
        print("  ⚠ БЕЗ ПРОГОНУ (--без-прогону): «виконано» скрізь 0, мітки справжні")
    elif службове["rc"]:
        print("  ⛔ ЖИВИЙ ШЛЯХ ВПАВ (код %s) — «не виконано» нижче НЕПОВНЕ: частина "
              "функцій не викликалась через поломку, а не через мертвість"
              % службове["rc"])
    print("=" * 78)
    print("%-22s %5s %5s %5s | %8s %5s %6s %6s"
          % ("модуль", "усьо", "вик", "ні", "продукт", "тест", "прилад", "НІХТО"))
    for r in рядки:
        print("%-22s %5d %5d %5d | %8d %5d %6d %6d"
              % (р_ім(r), r["усього"], r["виконано"], r["не_виконано"],
                 r["продукт"], r["тест"], r["прилад"], r["ніхто"]))
    print("-" * 78)
    print("%-22s %5d %5d %5d | %8d %5d %6d %6d"
          % ("РАЗОМ", усього, вик, усього - вик,
             c.get("продукт", 0), c.get("тест", 0), c.get("прилад", 0), c.get("ніхто", 0)))
    print()
    for м in МІТКИ:
        сп = [f for f in невиконані if f["мітка"] == м]
        if not сп:
            continue
        print("── НЕ ВИКОНАНО · МІТКА «%s» (%d) ──" % (м.upper(), len(сп)))
        if м == "ніхто":
            for f in сп:
                print("   %-22s %-40s :%d" % (f["модуль"], f["повне"], f["рядок"]))
        else:
            print("   (поіменно — у %s; тут лише лічба, бо список довгий)"
                  % os.path.relpath(ВИХІД, КОРІНЬ))
        print()
    print("«НІХТО» = %d — це і є вхід для наряду Н-02-03." % c.get("ніхто", 0))
    if службове["прогін"]:
        print("прогін живого шляху під профайлером: %.1f с (%d викликів у живих модулях)"
              % (службове["секунди"], службове["викликів"]))


def р_ім(r):
    return r["модуль"][:22]


