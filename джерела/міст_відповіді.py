def _питання_кодами(z):
    """Питання «код не знає» кодами (Ч-2, п.12): заяви знахідки → повідомлення виду
    `card_unchecked`. Знахідка без заяв дає None: такого рядка на картці нема (фрази коду
    жінці не підставляються), а звіт і діагноз руки називають його правилом."""
    з = [x for x in (z.get("заяви") or []) if isinstance(x, dict) and x.get("code") in _ВМ_в.ЗАЯВИ]
    return _ВМ_в.повідомлення("card_unchecked", *з) if з else None


# Коди питань про колір речей картки. Питання про профіль лишаються у звіті.
_КОЛІР_ПРО_ЦЕЙ_ОБРАЗ = frozenset({"cannot_tell_two_different_whites", "cannot_tell_two_neutrals_distinct",
                                  "cannot_tell_lightness_structure", "cannot_tell_item_is_neutral"})
# Межа системи, що стоїть у питаннях кольору поруч із заявою про речі: «площ не виміряно» однакова на кожній картці,
# тож у повідомленні картки її нема — вона йде у звіт ОДИН раз питанням `для_всіх`.
_МЕЖА_ПЛОЩ = "areas_not_measured"


def _для_всіх(повідомлення):
    """Межі системи адресовано журналу явно; наявність значень адресата не міняє."""
    заяви = (повідомлення or {}).get("statements") or []
    return int(bool(заяви) and all(з.get("recipient") == "journal" for з in заяви))


def _на_розгортання(повідомлення):
    """1 — питання кольору про речі цього образу (`_КОЛІР_ПРО_ЦЕЙ_ОБРАЗ`): картка несе його за
    кнопкою, а речення мовна модель пише лише тоді, коли жінка розгорне кнопку (`показ.html: питаннямиП`),
    тож збирання не чекає на них жодного виклику шару (п.9). Ознака — код заяви, не слова."""
    return int(any(з.get("code") in _КОЛІР_ПРО_ЦЕЙ_ОБРАЗ for з in (повідомлення or {}).get("statements") or []))


def _без_межі_площ(повідомлення):
    """Повідомлення картки без `areas_not_measured`: межа системи стоїть у звіті один раз
    питанням `для_всіх`, а не в кожному питанні кольору на картці. Решта заяв — як були."""
    заяви = [з for з in повідомлення.get("statements") or [] if з.get("code") != _МЕЖА_ПЛОЩ]
    return dict(повідомлення, statements=заяви)


def _з_кодами(повідомлення, запис):
    """Повідомлення, де кожен словник заяви з `item_id` дістав коди виду й кольору речі (`запис(id)` — запис
    картки; None — словник як був); коди, що вже стоять, лишаються."""
    def _д(v):
        """Додає коди у вкладених заявах повідомлення."""
        if isinstance(v, list):
            return [_д(x) for x in v]
        if not isinstance(v, dict):
            return v
        v = {к: _д(x) for к, x in v.items()}
        р = запис(v["item_id"]) if v.get("item_id") is not None else None
        коди = _ВМ_в.річ_заяви(dict(р, id=v["item_id"])) if isinstance(р, dict) else None
        for к in ("kind", "color"):
            if коди and коди.get(к) and к not in v:
                v[к] = коди[к]
        return v
    return dict(повідомлення, statements=_д(повідомлення.get("statements") or [])) if повідомлення else повідомлення


_СЛОВО_КОЛЬОРУ = ("colour_word_shop", "colour_word_shop_photo_other", "colour_word_model", "colour_word_not_photo",
                  "colour_partly_measured")


def _колір_речі(заява, і):
    """Заява-свідок кольору (`_СЛОВО_КОЛЬОРУ`) лише про річ `і`; None — річ у ній не названа. Слово
    крамниці з іншим кадром лишається таким лише тоді, коли кадр є в самої цієї речі."""
    речі = [x for x in ((заява.get("values") or {}).get("items") or []) if x.get("item_id") == і]
    if not речі:
        return None
    код = заява["code"]
    if код in ("colour_word_shop", "colour_word_shop_photo_other"):
        код = "colour_word_shop_photo_other" if речі[0].get("photo") else "colour_word_shop"
    return _ВМ_в.заява(код, items=речі[:1], item_ids=[і], source=заява.get("source", _ВМ_в.UNKNOWN))


def _пункти_картки(питання):
    """Пункти «неперевіреного» картки з питань суду (у їхньому порядку): пункт речі без виміру кольору
    (`_без_виміру`) і пункт правила. Пункт з одного питання — саме питання; з кількох — `правила`,
    `складові` (правило й повідомлення кожного), заяви без повторів; `на_розгортання` — лише коли всі
    складові такі. Питання `для_всіх` картка не малює — вони йдуть як є."""
    групи, за_ключем = [], {}
    for п in питання:
        if п.get("для_всіх") or not п.get("повідомлення"):
            групи.append((None, [п]))
            continue
        for к in [("річ", і) for і in п.get("_без_виміру") or []] or [("правило", п.get("правило"))]:
            if к not in за_ключем:
                за_ключем[к] = []
                групи.append((к, за_ключем[к]))
            за_ключем[к].append(п)
    пункти = []
    for к, члени in групи:
        чисті = [{кл: в for кл, в in ч.items() if кл != "_без_виміру"} for ч in члени]
        if len(члени) == 1 and (к is None or к[0] == "правило" or члени[0].get("_без_виміру") == [к[1]]):
            пункти.append(чисті[0])
            continue
        річ = к[1] if к[0] == "річ" else None
        заяви = [з for ч in члени for з in ч["повідомлення"]["statements"]]
        заяви = ([_колір_речі(з, річ) for з in заяви if з.get("code") in _СЛОВО_КОЛЬОРУ][:1]
                 + [з for з in заяви if з.get("code") not in _СЛОВО_КОЛЬОРУ]) if річ is not None else заяви
        заяви = list({_json.dumps(з, sort_keys=True, ensure_ascii=False): з for з in заяви if з}.values())
        правила = list(dict.fromkeys(ч.get("правило") for ч in члени))
        пункти.append(dict(правило=правила[0], правила=правила,
                           речі=[річ] if річ is not None else list(dict.fromkeys(
                               р for ч in члени for р in ч.get("речі") or [])),
                           повідомлення=_ВМ_в.повідомлення("card_unchecked", *заяви),
                           складові=[dict(правило=ч.get("правило"), повідомлення=ч.get("повідомлення"))
                                     for ч in чисті],
                           **({"на_розгортання": 1} if all(ч.get("на_розгортання") for ч in члени) else {})))
    return _лише_її(пункти)


