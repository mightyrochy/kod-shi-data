def _опори_номерами(опори, ном_о):
    """Опори образу — речі номерами пулу. Учасники несуть id (п.12), і `речі` опори
    будуються з них: назва в межах образу не однозначна («Other Brand» — взуття й браслет), і номер
    за назвою зливав дві речі в одну. Опора без учасників — номерами своїх `речі`, як доти."""
    вих = []
    for оп in опори:
        уч = [dict(у, річ=_ВМ.номер_речі(у["річ"], ном_о)) for у in оп.get("учасники") or []]
        вих.append(dict(оп, учасники=уч,
                        речі=(list(dict.fromkeys(у["річ"] for у in уч)) if уч else
                              [_ВМ.номер_речі(r, ном_о) for r in оп["речі"]])))
    return вих


