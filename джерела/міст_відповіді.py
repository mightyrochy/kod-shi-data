def _сценарій_для_суду(d, пак, намір):
    """Опис сценарію для судді (`сценарій.Сценарій`): поля нагоди з паспорта з їхнім джерелом і мітки шва з пакета.

    Мітки шва (смуга ошатності, шар ошатності, холод і траур пулу, спец палітри, межі людини, намір) пишуться в нагоду
    й стають полями опису з джерелом «виведене кодом» (`паспорт_нагоди.сценарій_з`: поле поза паспортом): опис один від
    межі моста до правила (наряд Код-сценарій-один-опис)."""
    с = d.get("сценарій") or {}
    сцен, _незн = _ПН.з_показу(с, d.get("паспорт"))
    if сцен.get("ошатність") not in (None, ""):
        сцен["_ошатність"] = сцен["ошатність"]
    _смуга_ош = _ФОРМ_СМ.смуга_ошатності(сцен)
    if _смуга_ош:
        сцен[_ФОРМ_СМ.ШТАМП_СМУГИ] = [_смуга_ош[0], _смуга_ош[1]]
    if сцен.get("формат") not in (None, ""):
        сцен["_формат"] = сцен["формат"]
    if пак.get("шар_ошатності"): сцен["шар_ошатності"] = пак["шар_ошатності"]
    if isinstance(пак.get("кандидати"), dict):
        сцен["холод_у_пулі"] = [сл for сл in _ПОГ_х.АКСЕСУАРИ_ХОЛОДУ if пак["кандидати"].get(сл)]
    if пак.get("_траур"): сцен["траур_пулу"] = пак["_траур"]
    if пак.get("_спец_палітри"): сцен["спец"] = пак["_спец_палітри"]
    if пак.get("_запити_у_фід"): сцен["запити"] = пак["_запити_у_фід"]
    if (пак.get("_спец_палітри") or {}).get("мисматч"):
        сцен["мисматч"] = пак["_спец_палітри"]["мисматч"]
    сцен["_жорстке_ні"] = d.get("жорстке_ні")
