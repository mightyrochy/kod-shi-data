    if _відп_схема == "ВИБІР_V1":
        _вибір = _розібрати_вибір(d, пак)
        d = dict(d, ід=list(_вибір["ід"]), текст_моделі=None)
    _ід_вх = d.get("ід") or []
    _ід_верх = (list(_ід_вх[-1]) if _ід_вх and isinstance(_ід_вх[0], (list, tuple))
                else list(_ід_вх))
    розбір = _розібрати_відповідь(d, пак, _відп_схема, _вибір, _ід_вх, _ід_верх)
    # Склад після вибору потрапляє в повний суд навіть після зміни «remove».
    в = _P.перевірити_від_моделі(
        _ід_верх, контекст.F, пак["_каталог"], контекст.T, сцен,
        спец_слоти=пак.get("_спец_слоти"), розбір=розбір.останній_образ,
        кандидати=пак["кандидати"], текст_моделі=розбір.вхід.get("текст_моделі"),
        розриви=розбір.розриви, драп=(d.get("драп") or None),
        частини=розбір.частини, місця=розбір.місця, прогін_руки=прогін_руки)
    d, в = _судити_набір(розбір, контекст, сцен, прогін_руки, в)
    try:
        _мсп = max(1, int(d.get("мова_спроба") or 1))
    except (TypeError, ValueError):
        _мсп = 1
    суд = _судити_склад(d, в, розбір, контекст, сцен, день, прогін_руки, _мсп)
    if суд.прийнята_заміна is not None:
        заміна = суд.прийнята_заміна
        _в0 = _json.loads(вхід) if isinstance(вхід, str) else dict(вхід)
        _нове = _json.loads(від_моделі(dict(_в0, ід=заміна["ід"], заміна_запасні=None,
                                            заміна_вирішена=1, текст_моделі=None, відповідь="ОБРАЗИ_V1"),
                                            прогін_руки=прогін_руки))
        _нове["заміна"] = заміна
        return _json.dumps(_нове, ensure_ascii=False, default=str)
    return _підготувати_результат(суд, розбір, контекст, сцен, вибір_схеми, день, прогін_руки)


