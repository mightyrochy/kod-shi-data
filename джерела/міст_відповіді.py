def _день_для_картки(d, в, розбір, _день_в):
    """Записує день і називає образи без запитаного опису дня."""
    _вибір = розбір.вибір
    _відп_схема = розбір.назва_схеми
    _ід_вх = розбір.ід_входу
    if _день_в and not в.get("джерело_образу"):
        в["день"] = _день_в
        if _вибір is not None:
            _обр = _вибір.get("замінено") or _вибір.get("обрано")
            _без_дня = ([_обр] if _обр and _вибір.get("ід") and not _вибір.get("день")
                        and not _вибір.get("слова_знято") else [])
        elif (_відп_схема == "ОБРАЗИ_V1" and d.get("текст_моделі") and not _ід_вх
              and not d.get("спроба_повноти")):
            _без_дня = [о.get("номер") for о in в.get("образи") or [] if not о.get("день")]
        else:
            _без_дня = []
        if _без_дня:
            в["день_не_написано"] = _без_дня
    if d.get("складено_кодом"):
        в["складено_кодом"] = str(d["складено_кодом"])
        в.pop("день_не_написано", None)


def _підготувати_результат(суд, розбір, контекст, сцен, _вс, _день_в, прогін_руки):
    """Оформлює результат суду для картки й повертає JSON моста."""
    d, в, _мсп = суд.вхід, суд.вердикт, суд.спроба_мови
