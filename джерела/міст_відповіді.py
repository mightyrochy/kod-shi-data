def _злити_частини(тексти, образів=None):
    """k відповідей на k частин пулу → ОДНА відповідь ОБРАЗИ_V1 і нотатки про те, як це вийшло.

    Читає кожну тією самою схемою, якою читається одна (`протокол.розбір_за_схемою`), а не
    склеює рядки: відповідь частини — самостійний JSON, і два JSON підряд не є JSON.
    ВІДПОВІДЬ, З ЯКОЇ НЕ ВИЙШЛО ЖОДНОГО ОБРАЗУ, НЕ КОВТАЄТЬСЯ: вона стає нотаткою з номером
    частини, а решта частин їде далі — інакше одна впала частина мовчки забирала б третину
    пулу. Коли жодна частина не дала образів, віддається ПЕРШИЙ текст як є: далі його прочитає
    звичайний шлях і скаже те саме, що сказав би на одному виклику (повторний виклик чи
    чесна відмова), а не «образів нема» без причини.
    `ід` перенумеровується наскрізно («o1», «o2»…): модель нумерує в межах СВОЄЇ відповіді,
    і три «o1» в одному переліку були б трьома іменами одного образу.
    `образів` — скільки просить цілий пакет: частина і просила свою частку (`пакет_моделі.
    частини_пакета`), і береться до неї — частина, що переписала понад, не витісняє
    сусідніх."""
    k = len(тексти or [])
    сп = [(ч_, т_) for ч_, т_ in enumerate(тексти or []) if isinstance(т_, str) and т_.strip()]
    образи, нотатки = [], []
    for і, (ч_, т_) in enumerate(сп, 1):
        об, чому, _нот = _ПР.розбір_за_схемою(т_, "ОБРАЗИ_V1")
        част = (об or {}).get("образи") if isinstance(об, dict) else None
        if not част:
            нотатки.append("частина %d з %d не дала жодного образу%s"
                           % (і, len(сп), (": %s" % чому) if чому else ""))
            continue
        if образів:
            частка = образів // k + (1 if ч_ < образів % k else 0)
            if len(част) > частка:
                нотатки.append("частина %d з %d дала %d образів, просили %d — узято перші %d"
                               % (і, len(сп), len(част), частка, частка))
                част = част[:частка]
        for о in част:
            if isinstance(о, dict):
                образи.append(dict(о, ід="o%d" % (len(образи) + 1)))
    if not образи:
        return (сп[0][1] if сп else ""), нотатки
    if нотатки:
        нотатки.append("злито образів %d із %d частин" % (len(образи), len(сп)))
    return _json.dumps({"версія": _ПР.ВЕРСІЯ, "образи": образи},
                       ensure_ascii=False, default=str), нотатки



