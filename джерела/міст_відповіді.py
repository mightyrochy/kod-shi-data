    _обр_п = _вс.get("обрала") or {}
    _звіт_палітри(в, контекст, _вс, _вк, _обр_п, прогін_руки)
    _ід_сх = set((в.get("повнота") or {}).get("ід") or [])
    _речі_сх = ([r for r in (в.get("речі") or []) if r.get("id") in _ід_сх]
                if _ід_сх else (в.get("речі") or []))
    _за_ід_сх = {c["id"]: c for c in (пак.get("_каталог") or []) if c.get("id")}
