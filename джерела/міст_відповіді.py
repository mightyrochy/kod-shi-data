def _додати_речі_за_запитом(d, в, пак, сцен, прогін_руки):
    """Шукає запитані моделлю речі та доповнює пул і журнал."""
    _потрібно = _P.запити_речей_з_тексту(d.get("текст_моделі"))
    в["запропоновано"] = []
    if _потрібно:
        _пасп = d.get("паспорт") if isinstance(d.get("паспорт"), dict) else {}
        _слоти_кат = {r.get("слот") for r in пак["_каталог"]}
        for _зап in _потрібно:
            _фраза, _слот = _зап.get("фраза") or _зап["опис"], _зап.get("слот")
            _коди = _зап.get("коди") or _ВМ_в.UNKNOWN
            _де = (пак["_каталог"] if _слот not in _слоти_кат else
                   [r for r in пак["_каталог"] if r.get("слот") in пак["кандидати"]
                    and (r.get("слот") == _слот or _слот in (r.get("слоти_альт") or ()))])
            _зн = _P.шукати_словами(_де, _фраза, n=4, смуга_погоди=сцен.get("смуга_погоди"), вето=_P.вето_чинне(_пасп), прогін_руки=прогін_руки)   # пошук за її бажанням — теж лише чинні межі
            for _r in _зн:
                _сл = _r.get("слот")
                if _сл in пак["кандидати"]:
                    _додати_за_запитом(пак, _сл, _r, _коди)   # і в реєстр ключа пакета: кеш витісняє
                в["запропоновано"].append(dict(id=_r.get("id"), назва=str(_r.get("назва") or ""), слот=_сл, запит=_фраза,
                                                **({"слот_запиту": _слот} if _слот else {})))


def _скласти_вердикт_образів(d, в, пак, сцен, розбір, _поперед, _сп_пвн, _день_в, _рем, _вип):
    """Складає вердикт набору та переносить прийняті рішення вибору."""
    _вибір = розбір.вибір
    _іт = d.get("ітерація") or 1
    _відп_об = (_ПР.розбір_за_схемою(d["текст_моделі"], "ОБРАЗИ_V1")[0]
                if (_поперед and d.get("текст_моделі")) else None)
    if _поперед:
        for _о, _утр in zip(в["образи"], _P.утрачені_опори(в["образи"], _поперед)):
            if _утр:
                _о["утрачені_опори"] = _утр
    _вип_п = ((пак.get("пакет") or {}).get("випадок") if isinstance(пак.get("пакет"), dict) else None) or {}
    в["вердикт"] = _P.вердикт_v1(в["образи"], варіантів=_рем, випадок=_вип,
                                   намір=_вип_п.get("намір") or сцен.get("intent"),
                                   мета=_вип_п.get("мета") or (d.get("паспорт") or {}).get("мета"),
                                   кандидати=пак.get("кандидати"), каталог=пак.get("_каталог"),
                                   ітерація=_іт,
                                   попередній_вердикт=_поперед,
                                   відповідь_моделі=_відп_об,
                                   мова=в.get("мова"), реєстри=в.get("реєстри"))
    if _вибір is not None and _вибір.get("обрано") and _вибір.get("прийнято"):
        _P.прийняти_гейти(в["вердикт"], _вибір["прийнято"])
    if _сп_пвн and d.get("вибір_повноти"):
        _P.донести_прийняття_вибору(в["вердикт"], d["вибір_повноти"],
                                     кандидати=пак["кандидати"], каталог=пак["_каталог"])
        _після_вибору = {о["ід"]: о for о in в["вердикт"]["образи"]}
        for _о in в["образи"]:
            if _о.get("номер") in _після_вибору:
                _зап = _після_вибору[_о["номер"]]
                _о["знахідки"] = _зап["знахідки"]
                _о["свідомі"] = _зап.get("свідомі") or []
    if _день_в:
        в["вердикт"]["день"] = _день_в
    _пом = _ПР.перевірити(_ПР.СХЕМИ["ВЕРДИКТ_V1"], в["вердикт"])
    if _пом:
        в["протокол_помилки"] = _пом
    return _іт


