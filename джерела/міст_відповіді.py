def _вердикти_образів(d, F, T, сцен, пак, _PL, основний=None, розбір=None):
    """По вердикту на кожен образ у відповіді моделі — запис для показу й журналу
    з полями, з яких `pipeline.вердикт_v1` складає обʼєкт `ВЕРДИКТ_V1`.

    `ід` може прийти й напряму: списком id (один образ) або списком списків (N).
    Порядок збережено як у тексті — це не ранг. `номер` («о1», «о2», …) — позиція
    в цьому порядку; ним модель називає образ, а «з-о1-3» — знахідку в ньому.

    ЩО ЗНИКЛО (Т-03). `_стислі_знахідки` лишала пʼять полів і губила `регістр` і
    `ремонт` — єдине поле, яке каже, ЩО РОБИТИ. Рядки знахідок тепер будує
    `pipeline.знахідки_вердикту` (стеля категорії, злиття за правилом, стабільний
    `ід`), і одиничний образ іде тим самим будівником, що й N: доти він брав
    `основний` уже стиснутим, без реєстрів і чеклістів.

    `розбір` — уже розібрана відповідь моделі (`pipeline.образи_з_тексту`) від
    верхнього рівня: той самий текст не має розбиратись двічі, і, головне, обидва
    рівні мусять бачити ОДИН І ТОЙ САМИЙ поділ на образи (Т-04, Н-V33-060 крок 4).
    """
    ід = d.get("ід")
    _частини_н = {}
    підписи, блоки, розриви = {}, {}, {}
    if ід and isinstance(ід, (list, tuple)) and ід and isinstance(ід[0], (list, tuple)):
        набори = [list(x) for x in ід]
    elif ід:
        набори = [list(ід)]
    elif d.get("текст_моделі"):
        _роз = розбір if розбір is not None else _PL.образи_з_тексту(
            d["текст_моделі"], кандидати=пак["кандидати"], каталог=пак["_каталог"])
        набори = [(р.get("ід") or []) for р in _роз]
        _частини_н = {tuple(р.get("ід") or []): (р.get("частини") or {}) for р in _роз}
        # ── СКІЛЬКИ БЛОКІВ БУЛО І СКІЛЬКИ ДІЙШЛО (02.09.2026) ──────────────
        # Нижче `набори = [н for н in набори if н]` викидає образ, у якому жоден
        # id не резолвився (усі пари невірні, чужий магазин, вигадані id). Він
        # зникав без сліду: «просила 10, дістала 7» читалось як «модель дала 7».
        # Тепер лічба їде назовні полем `розбір_блоків`; показ друкує її в діагноз.
        d["_розбір_блоків"] = dict(
            блоків=len(_роз), з_id=sum(1 for р in _роз if р.get("ід")),
            без_id=[dict(підпис=р.get("підпис"), невідомі=(р.get("невідомі") or [])[:6],
                         невірні_пари=(р.get("невірні_пари") or [])[:6])
                    for р in _роз if not р.get("ід")][:5])
        підписи.update({tuple(р.get("ід") or []): р.get("підпис") for р in _роз if р.get("ід")})
        # БЛОК ТЕКСТУ НА ОБРАЗ. Без нього рядок «СВІДОМО: <річ> — <чому>» не доходив
        # до вердикту жодного з N образів: `перевірити_від_моделі` кликався без
        # тексту взагалі. Наслідок був зворотний до задуманого — ші пояснювала свій
        # хід, код цього не чув, і друга ітерація діставала цей хід у списку «що
        # знайшов код», тобто її просили полагодити те, що вона зробила навмисно.
        блоки.update({tuple(р.get("ід") or []): р.get("текст") for р in _роз if р.get("ід")})
        # ОГОЛОШЕНІ ХОДИ — ПОЛЕМ, А НЕ ПОШУКОМ У БЛОЦІ (Т-04). На JSON-шляху
        # оголошення живе в `образ.свідомо` з адресатом; блок тексту тут несе лише
        # прозу моделі (підпис, «чому») і на нього мовний гейт, а не розриви.
        розриви.update({tuple(р.get("ід") or []): р["свідомі"]
                        for р in _роз if р.get("ід") and р.get("свідомі") is not None})
    else:
        return []
    набори = [н for н in набори if н]
    # НОМЕРИ — З ПОВНОГО ПУЛУ, як їх бачила модель (ті самі, що в `образ_рядком`).
    ном = (_PL.номери_речей(пак["кандидати"])[0]
           if (пак.get("кандидати") and _PL.ПАКУВАТИ_ІНДЕКСОМ) else {})
    # ── РЕЧІ, ВІДНОВЛЕНІ З КАТАЛОГУ: ОДИН РАЗ НА НАБІР (Т-10) ─────────────────
    # `перевірити_від_моделі` віддає речі вже стиснутими до {id, слот, назва} —
    # без `lab` і без `крій`, тобто без того, з чого рахуються колірна схема,
    # літера силуету й герой. Тому вони відновлюються тут — тим самим
    # `composer._у_річ`, яким уже рахувалась попарна близькість набору (нижче),
    # і одним проходом на обох споживачів: другий такий цикл розійшовся б із
    # першим першою ж правкою складу образу (половина комплекту, `частини`).
    # У ЗАПИС ЇДУТЬ РИСИ, А НЕ РЕЧІ: запис читають показ і журнал, і класти туди
    # повні речі каталогу означало б подвоїти вантаж заради трьох ознак.
    import composer as _КМ0
    _за_ід = {c.get("id"): c for c in (пак.get("_каталог") or [])}
    _повні = []
    for н in набори:
        try:
            _повні.append([_КМ0._у_річ(dict(_за_ід[i]), _за_ід[i]["слот"], T)
                           for i in н if i in _за_ід])
        except Exception as _e:
            # речі поза каталогом пакета не мають права зронити вердикт
            import os as _os, traceback as _tb   # п.14: не мовчати
            if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
            _повні.append([])

    def _запис(н, о, і, підпис=None, перевірено=True, близькість=None):
        """Один образ: те, що читали показ і журнал (`ід`, `блокує`, `свідомі`,
        `вузол`…), плюс поля схеми (`номер`, `речі_н`, `блокери`, `чекліст`).
        Реєстрові знахідки (K-REG-*) лежали окремим відром і в промпт ішли
        окремим абзацом — тепер це знахідки образу, як усі."""
        номер = "о%d" % і
        реєстрові = list(((о.get("реєстри") or {}).get("знахідки")) or [])
        речі = [dict(id=r.get("id"), слот=r.get("слот"), назва=r.get("назва"),
                     **({"частина_комплекту": r["частина_комплекту"]}
                        if r.get("частина_комплекту") else {}))
                for r in (о.get("речі") or [])]
        # РІЧ У ЗНАХІДЦІ БУВАЄ НАЗВОЮ, НЕ id (`реєстри.перевірити`, K-PAL-16 у
        # composer): у межах ЦЬОГО образу назва однозначна, тож номер дістає й вона.
        _ном_о = dict(ном)
        for r in речі:
            if r.get("назва") and r.get("id") in ном:
                _ном_о.setdefault(r["назва"], ном[r["id"]])
        рядки, вето = _PL.знахідки_вердикту(list(о.get("знахідки") or []) + реєстрові,
                                            номер, _ном_о)
        return dict(ід=list(н), номер=номер, підпис=підпис, перевірено=bool(перевірено),
                    блокує=о.get("блокує") or [],
                    блокери=_PL.блокери_структури(о.get("блокує") or [], речі, ном) + вето,
                    речі_н=[_PL.номер_речі(r["id"], ном, r.get("частина_комплекту")) for r in речі],
                    # СЛОТ РЕЧІ ЇДЕ РАЗОМ ІЗ ЇЇ НОМЕРОМ (18.09.2026). `речі_н` —
                    # самі номери, і `pipeline.різноманітність` по них не могла
                    # сказати, ЩО саме повторюється в наборі: «одне взуття на 10
                    # образів» і «одна каблучка» читались однаково. Мапа будується
                    # тут, бо тут — і лише тут — слот і номер лежать поруч
                    # (`речі` несуть `слот`, `речі_н` рахуються з тих самих `речі`).
                    слоти_н={_PL.номер_речі(r["id"], ном, r.get("частина_комплекту")): r["слот"]
                             for r in речі if r.get("слот")},
                    знахідки=рядки,
                    # ОГОЛОШЕНИЙ ХІД ЇДЕ ПОЛЯМИ, А НЕ ОДНИМ РЯДКОМ (рядок 9 дошки).
                    # `текст` лишається — його читають показ, журнал і шапка прозового
                    # вибору; `річ` (номер «#48·06») і `чому` додано, бо без них
                    # вердикт не можна прочитати назад: крок вибору (виклик 3) дістає
                    # рівно цей обʼєкт і мусить знайти в ньому адресата оголошення.
                    свідомі=[dict({k: с[k] for k in ("річ", "чому") if с.get(k)},
                                  текст=с.get("текст"))
                             for с in (о.get("свідомі") or [])],
                    вузол=о.get("вузол"), рядок_вузла=о.get("рядок_вузла"),
                    поза_кандидатами=о.get("поза_кандидатами"),
                    риси=_PL.риси_образу(_повні[і - 1] if і - 1 < len(_повні) else [],
                                         T, _ном_о),
                    # СЕРЕДНЯ ПОПАРНА БЛИЗЬКІСТЬ — У ЗАПИС (рядок 5 дошки). Число
                    # вже пораховане нижче одним проходом на весь набір, і воно ж
                    # є єдиним входом рангу K-COMP-01. Без нього `вердикт_v1` не
                    # мав із чого скласти `набір.координація`: поле стояло в схемі
                    # третій тиждень і не мало писача — `coordination.координація`
                    # кладе свій вирок у `знахідки` образу, тобто в інше місце.
                    близькість=близькість,
                    чекліст=_PL.чекліст_вердикту(о.get("чеклісти")))

    if len(набори) <= 1 and основний is not None:
        # ── ОДИН ОБРАЗ: ДРУГОГО ПРОГОНУ НЕ ТРЕБА, І ТЕПЕР ЦЕ ПРАВДА (Н-V33-060) ──
        # Ранній вихід тут стояв заради економії найдорожчого прогону — і доти
        # МОВЧКИ ГУБИВ оголошені ходи: `основний` судився всім текстом відповіді,
        # де рядка «СВІДОМО:» на JSON-шляху не було зовсім (V33). Знімати вихід
        # означало б два прогони судді на один образ у найчастішому випадку —
        # фінальному виклику показу, де людина вже чекає. Тому полагоджено джерело:
        # верхній рівень (`від_моделі`) тепер судить ОСТАННІЙ образ його ж блоком і
        # його ж оголошеннями, а при одному образі останній — це він і є.
        return ([_запис(набори[0], основний, 1, підписи.get(tuple(набори[0])),
                        основний.get("перевірено", True))] if набори else [])
    # ── НАБІР ДЛЯ K-COMP-01: ІНШІ ОБРАЗИ ЦЬОГО САМОГО ВИПАДКУ (08.09.2026) ──
    # Правило міряє ПОЗИЦІЮ В НАБОРІ, не абсолютну відстань (Gray та ін. 2014), і
    # без набору чесно утримується. Набір є рівно тут і більше ніде: N образів,
    # які модель дала на один випадок, — це і є те, між чим обирає людина.
    # Перший прохід рахує лише одне число на образ (середню попарну близькість), і
    # він дешевий: жодного судження, тільки колір уже відновлених із каталогу речей
    # (`_повні` вище — той самий один прохід, що годує риси образу для Т-10).
    _близькості = [(_PL.близькість_образу(_реч) if _реч else None) for _реч in _повні]
    вих = []
    for _і, н in enumerate(набори):
        # набір — ІНШІ образи, не цей: інакше образ ранжувався б проти себе самого
        _інші = [v for j, v in enumerate(_близькості) if j != _і and v is not None]
        try:
            о = _PL.перевірити_від_моделі(list(н), F, пак["_каталог"], T, сцен,
                                          спец_слоти=пак.get("_спец_слоти"),
                                          кандидати=пак["кандидати"],
                                          текст_моделі=блоки.get(tuple(н)),
                                          драп=(d.get("драп") or None),
                                          частини=_частини_н.get(tuple(н)),
                                          набір_близькостей=_інші,
                                          розриви=розриви.get(tuple(н)))
        except Exception as _e:
            вих.append(dict(ід=list(н), номер="о%d" % (_і + 1), перевірено=False,
                            чому="%s: %s" % (type(_e).__name__, _e)))
            continue
        вих.append(_запис(н, о, _і + 1, підписи.get(tuple(н)), о.get("перевірено", True),
                          близькість=_близькості[_і]))
    return вих


def _вердикт_для_моделі(вердикт):
    """Вердикт для ПРОМПТА: той самий обʼєкт без кодів правил (§1(г), до рішення Р-1).

    Модель бачить `ід` знахідки й `суть`, код — коди: те саме, що доти робив
    `_без_ід_рядків` над прозою. Ключ `правило` знімається цілком (у знахідках і в
    `мова.порушення`), а не лишається порожнім рядком після вирізання; коди
    всередині текстів (рядок вузла) вирізає `_без_ід_глибоко`. Схемою ця копія НЕ
    перевіряється й не мусить: контракт «ВЕРДИКТ_V1» тримає обʼєкт у `в["вердикт"]`.
    """
    def _без_правила(x):
        if isinstance(x, dict):
            return {k: _без_правила(v) for k, v in x.items() if k != "правило"}
        if isinstance(x, (list, tuple)):
            return [_без_правила(v) for v in x]
        return x
    return _без_ід_глибоко(_без_правила(вердикт))


def від_моделі(вхід):
    """Образ, який зібрала модель, крізь той самий гіперграф (pipeline.перевірити_від_моделі).
    Вхід: {…той самий випадок…, каталог, ід: [...], текст_моделі?}."""
    СЛ.почати()
    d = _json.loads(вхід) if isinstance(вхід, str) else вхід
    d = _нормалізувати_вхід(_застосувати_паспорт(d))
    import pipeline as _PL
    # ── РУКА 2 СУДИТЬСЯ СВОЇМ ПУЛОМ, А НЕ ЛЮДСЬКИМ ────────────────────────────
    # ЩО БУЛО ЗЛАМАНО. `запити` будує руці C кандидатів ДОНОРА (інша людина —
    # інші вікна), а стенд слав сюди той самий `вх` для всіх чотирьох рук. Тобто
    # образ, зібраний із донорських речей, судився обличчям і тілом ЛЮДИНИ.
    # ЗМІРЯНО на каталог_повний (профіль #f2d6c4/#4a4644, побачення-кафе-19:00):
    # пули перетинаються на 26.7 % (у слоті «верх» — 0 %), усі 4 речі образу руки 2
    # лягали як `поза_кандидатами`, а першим рядком промпта ремонту йшла знахідка
    # K-CLR-02 «контраст біля обличчя нижчий за власний» силою 1.00 — порахована
    # проти обличчя ЛЮДИНИ. При судженні донором її нема взагалі.
    # ЧОМУ ЦЕ Б'Є ПО ЕКСПЕРИМЕНТУ, А НЕ ЛИШЕ ПО ЛОГУ. Промпт ремонту — це друга
    # ітерація: модель просили тягнути донорський образ до палітри людини, тобто
    # плече 2 сходилось до плеча 1 рівно там, де вимірюється різниця між ними.
    # ЧОГО ЦЕ НЕ ЛАМАЛО (теж зміряно): список кандидатів у промпт ремонту не
    # тече — з 8 id там 8 донорських і 0 суто людських. Витік був через вердикт.
    # `донор` від показу означає «це рука 2», а не «бери донора»: що саме зламано,
    # вирішує той самий жереб, що й у `запити` (`_рука2`, 04.09.2026).
    _рука_2 = bool(d.get("донор"))
    F, T, зріст, kw = _збірка(d)
    якір = _якір(d); намір = d.get("намір") or "conventional"
    п = _пакет(F, T, зріст, kw, якір, намір, _самозвіт(d), d.get("вибір_кольору"),
               d.get("драп"))
    гілка = (None if d.get("гілка") is None
             else min(int(d["гілка"]), len(п["палітри"]["розвилка"]) - 1))
    _поломки_2 = set()
    _поломка_2 = None
    _донор = False
    # ЛЮДИНА ЗАПАМ'ЯТОВУЄТЬСЯ ДО ПІДМІНИ ДОНОРОМ: бриф руки 2 інвертує метал
    # ВІДНОСНО РУКИ B (`brief.перекинути_метал`), тож без людського плеча той
    # самий набір правил тут не відтворити — а відтворити його треба, див. нижче.
    _пЛ, _T_Л, _гЛ = п, T, гілка
    if _рука_2:
        (_поломки_2, F, T, п, гілка, _сц2, _текст2, _, _,
         _поломка_2, _пасп2) = _рука2(d, гілка, F, T, п, зріст, kw, якір, намір)
        _донор = "донор" in _поломки_2
        # `випадок` — зіпсований текст, а `паспорт` — зіпсований паспорт, точно як
        # `d2` у `запити`: пакет руки 2 мусить нести той самий випадок, яким
        # складали, інакше ключ кеша й довжина пакета розійдуться між складанням і
        # судом, а паспорт (він переважає сценарій) поверне поломку назад.
        d = dict(d, сценарій=_сц2, випадок=_текст2, паспорт=_пасп2)
    # ── ПРАВИЛА ДЛЯ ПАКЕТА — ТІ САМІ, ЩО В `запити` (Т-02) ───────────────────
    # З Т-02 бриф правил лежить у `ПАКЕТ_V1.правила`, а бюджет міряє ПОВНИЙ JSON
    # пакета — тобто набір правил через довжину впливає на зріз пулу. Якби суд
    # будував пакет без правил, він дістав би ІНШИЙ пул, і номери «#412·29» з
    # відповіді моделі резолвились би в інші речі (той самий дефект нумерації,
    # що на вітрині 02.09). Тому обидва ендпойнти кличуть одне джерело.
    _б_B, _б_C, _ = _брифи(d, _пЛ, _T_Л, _гЛ, п, T, гілка,
                         "ремесло" in _поломки_2, d.get("вимоги") or "")
    # гілка за замовчуванням — так само, як у `запити`: суд мусить іти тим самим
    # пулом, яким складали, інакше речі образу лягли б «поза кандидатами» (Н-V05-015)
    пак = _пакет_каталогу(d, F, T, п, (0 if гілка is None else гілка),
                          за_замовчуванням=(гілка is None),
                          правила=(_б_C if _рука_2 else _б_B)["правила"],
                          рука2=_рука_2)
    if not пак.get("готово"):
        return _json.dumps(dict(перевірено=False, чому=пак.get("чому")), ensure_ascii=False)
    с = d.get("сценарій") or {}
    сцен, _незн = СЦ.з_показу(с, d.get("паспорт"))
    if сцен.get("ошатність") not in (None, ""): сцен["_ошатність"] = сцен["ошатність"]
    if сцен.get("формат") not in (None, ""): сцен["_формат"] = сцен["формат"]
    # вхід K-ACC-07: специфікація палітри й вікна у фід — див. `_пакет_каталогу`
    if пак.get("_спец_палітри"): сцен["спец"] = пак["_спец_палітри"]
    if пак.get("_запити_у_фід"): сцен["запити"] = пак["_запити_у_фід"]
    # вето зон і «не носитиму» — і в суддю (pipeline знімає їх у _оцінити)
    сцен["_жорстке_ні"] = d.get("жорстке_ні"); сцен["_вето"] = d.get("вето")
    # ── САМОЗВІТ І НАМІР ДОЇЖДЖАЮТЬ ДО СУДДІ (17.09.2026) ───────────────────
    # ДВІ СЕСІЇ ЗНАЙШЛИ ЦЕЙ ШОВ ОДНОГО ДНЯ З РІЗНИХ БОКІВ, І ПРИЧИНА В НИХ ОДНА.
    # `перевірити_від_моделі` передає `сцен` у `composer._оцінити` як
    # `**сценарій`, а звідти воно їде в `pipeline.перевірити_образ(**kw)`. Сюди ж
    # `сцен` приходить із `СЦ.з_показу`, де ні самозвіту, ні наміру нема — на
    # відміну від `запити`, де обидва в сценарій кладуться.
    #   САМОЗВІТ (K-PAL-16): `_оцінити` бере його для `palettes.осі` під
    #     «контекст втягує межовий колір; неактивне, коли бік температури людини
    #     невідомий». Жінка називає «срібло», пул це чує (вікна будуються з
    #     самозвітом), а СУД на тому самому прогоні бачить вісь тону 0.00 — тобто
    #     правило не могло спрацювати НІКОЛИ, навіть коли бік названий.
    #   НАМІР: `d["намір"]` доходив рівно до `_пакет` (розвилка палітри,
    #     СМІЛИВІ_НАМІРИ) і зупинявся там, а `перевірити_образ` читає його як
    #     `kw.get("intent", "conventional")`. Отже суддівський бік бачив
    #     «conventional» ЗАВЖДИ — і гейт наміру (`реєстр_правил._гейт_наміром`,
    #     який тримає п'ять рахункових правил: K-COL-02, K-COMP-03, K-COMP-04,
    #     K-INT-04, K-COL-05), і підлога інтересу з порогом 2 для
    #     fashion_forward, і K-COMP-06 (фактура перша у стриманому контексті)
    #     працювали не за наміром жінки, а за дефолтом. Виміряно: під `statement`
    #     пакет давав ІНШИЙ пул (гілок 6 проти 4), а вердикт над тим самим
    #     образом виходив побуквенно однаковий.
    # ЧОМУ САМЕ ТУТ, А НЕ В `з_показу`: ключ `intent` уже оголошений службовим у
    # `сценарій.СЛУЖБОВІ`, але покласти його у ВХІДНИЙ сценарій не можна —
    # `_пакет` передає намір у `підготувати` ще й іменованим аргументом, і той
    # самий ключ із `**_мк` дав би TypeError «multiple values for intent». Тут
    # пакет уже зібраний, і колізії нема. `setdefault`, а не присвоєння: паспорт
    # має право переважити, і він це вже зробив у `з_показу` вище.
    if d.get("самозвіт"): сцен["самозвіт"] = _самозвіт(d)
    сцен.setdefault("intent", намір or "conventional")
    # ── `ід` СПИСКОМ СПИСКІВ: N ОБРАЗІВ ІДЕНТИФІКАТОРАМИ, БЕЗ ТЕКСТУ ─────────
    # ЩО ЦЕ МІНЯЄ (правило 3, 08.09.2026). `_вердикти_образів` цей вхід ОГОЛОШУЄ
    # в докстрінгу («списком id (один образ) або списком списків (N)») і вміє
    # його читати — а верхній рівень не вмів: `list(d["ід"])` їхало прямо в
    # `перевірити_від_моделі`, де `i not in за_ід` падало
    # `TypeError: unhashable type: 'list'`. Тобто оголошена половина контракту
    # валила ендпойнт ЦІЛКОМ, ще до другого проходу. Показ цього не бачив, бо
    # шле `текст_моделі`; побачила батарея гейта, яка вперше покликала
    # `від_моделі` з N образами (крок аудиту A9).
    # ЧОМУ ОСТАННІЙ, А НЕ ПЕРШИЙ: верхній рівень і в текстовому шляху — вердикт
    # по ОСТАННЬОМУ образу (див. коментар біля `в["образи"]` нижче).
    # ── ВИБІР І ОПИС ЧИТАЮТЬСЯ СВОЇМИ СХЕМАМИ (Т-06) ──────────────────────────
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ. Виклики 3 і 4 приходили сюди тим самим каналом, що
    # виклик 1: `текст_моделі` розбирався як ОБРАЗИ_V1, бо прозовий вибір САМ
    # перераховував склад образу рядком «ОБРАЗ: …». Тобто код просив модель
    # скопіювати те, що щойно їй сказав, і вірив копії. Тепер `ВИБІР_V1` несе
    # `обрано` — ід образу з ТОГО САМОГО вердикта (`вибір_над`), і склад береться
    # з нього, а не з копії; `ОПИС_ВІДПОВІДЬ_V1` несе прозу, і в суд їде рівно
    # вона, а не весь обʼєкт.
    # ЯК ВОНО ВКЛАДАЄТЬСЯ В РЕШТУ ШЛЯХУ: обидва режими зводяться до `ід` —
    # найстарішого й найпростішого входу цього ендпойнта. Нижче нічого не знає ні
    # про вибір, ні про опис, і не мусить.
    _відп_схема = str(d.get("відповідь") or "ОБРАЗИ_V1")
    _вибір = _опис_відп = None
    if _відп_схема == "ВИБІР_V1":
        _вибір = _PL.вибір_з_json(d.get("текст_моделі"), d.get("вибір_над") or {},
                                  кандидати=пак["кандидати"], каталог=пак["_каталог"])
        d = dict(d, ід=list(_вибір["ід"]), текст_моделі=None)
    elif _відп_схема == "ОПИС_ВІДПОВІДЬ_V1":
        _опис_відп = _PL.опис_відповідь_з_json(d.get("текст_моделі"),
                                               кандидати=пак["кандидати"],
                                               каталог=пак["_каталог"])
        # У суд і в мовний гейт іде ПРОЗА, яку прочитає жінка, а не обʼєкт цілком.
        d = dict(d, текст_моделі=_опис_відп["проза"])
    _ід_вх = d.get("ід") or []
    _ід_верх = (list(_ід_вх[-1]) if _ід_вх and isinstance(_ід_вх[0], (list, tuple))
                else list(_ід_вх))
    # ── ВІДПОВІДЬ РОЗБИРАЄТЬСЯ ОДИН РАЗ, І ОГОЛОШЕНІ ХОДИ ТУТ — ОСТАННЬОГО ОБРАЗУ ──
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ (Т-04, Н-V33-060 кроки 3–4). Верхній рівень діставав
    # УВЕСЬ текст відповіді, і з нього брались розриви. На JSON-шляху це давало
    # НУЛЬ (рядка «СВІДОМО:» в обʼєкті нема — V33): оголошений хід не послаблював
    # нічого, і фінальний вердикт показу, промпт опису й картка жінки його не
    # бачили. На прозовому шляху це давало ЗАНАДТО БАГАТО: пояснення третього
    # образу послаблювало знахідку в сьомому. Тепер розбір один на обидва рівні, а
    # верхній рівень — вердикт по ОСТАННЬОМУ образу (див. коментар біля
    # `в["образи"]` нижче), тож і оголошення йому належать останнього.
    # ТЕКСТ лишається ЦІЛИЙ: його читач — мовний гейт, а російське в третьому блоці
    # є російським у відповіді, і звужувати йому зір нема за що.
    _розбір_відп = (_PL.образи_з_тексту(d["текст_моделі"], кандидати=пак["кандидати"],
                                        каталог=пак["_каталог"])
                    if d.get("текст_моделі") and not _ід_вх else None)
    _остан = next((р for р in reversed(_розбір_відп or []) if р.get("ід")), None)
    в = _PL.перевірити_від_моделі(_ід_верх, F, пак["_каталог"], T, сцен,
                                  спец_слоти=пак.get("_спец_слоти"),
                                   кандидати=пак["кандидати"], текст_моделі=d.get("текст_моделі"),
                                   # ── ОГОЛОШЕНИЙ ХІД ПЕРЕЖИВАЄ КРОК ВИБОРУ (рядок 9) ──
                                   # `ВИБІР_V1` несе `обрано` і `чому` — оголошенню в
                                   # ній місця нема й не буде: ші оголосила хід на
                                   # ітерації 2, і вдруге переказувати його не мусить.
                                   # Тому розриви беруться з ТОГО САМОГО вердикта, над
                                   # яким робився вибір (`вибір_над` → `образ.свідомі` →
                                   # `вибір_з_json.розриви`), — так само, як звідти ж
                                   # береться склад образу й `частини`.
                                   розриви=((_вибір.get("розриви") or None) if _вибір
                                            else (_остан.get("свідомі") if _остан else None)),
                                   драп=(d.get("драп") or None),
                                   # ПОЛОВИНА КОМПЛЕКТУ ДОЇЖДЖАЄ Й НА ШЛЯХУ `ід` (Т-06):
                                   # на виборі склад приходить номерами вердикта, серед них
                                   # буває «#12·03/низ». Без цього той самий образ судився б
                                   # на виклику 3 інакше, ніж на виклику 2 (там `частини`
                                   # бере `_вердикти_образів`), і структура бачила б комплект
                                   # там, де модель узяла з нього одну річ.
                                   частини=(_вибір["частини"] if _вибір else None))
    # ── РУКИ БЕЗ КАТАЛОГУ (3/4): модель ВИГАДАЛА речі, id у тексті нема, але є рядки
    # «річ … #hex» — тоді образ будується з тексту тим самим шляхом, що й фід
    # (pipeline.речі_з_тексту), і граф ганяється на вигаданих речах. Інакше вердикти
    # цих рук лягали б у лог без знахідок коду (28.08.2026).
    if not в.get("перевірено") and d.get("текст_моделі") and not (в.get("розбір") or {}).get("ід") \
            and _PL._HEX_РЕГ.search(d["текст_моделі"]):
        в = _PL.перевірити_образ_моделі(d["текст_моделі"], F, T,
                                        {k: v for k, v in сцен.items() if not str(k).startswith("_")})
        в["джерело_образу"] = "текст моделі (без каталогу)"
    в.pop("граф_повний", None)
    # ── СТЕЛЯ КАТЕГОРІЇ Й ПІДЛОГА — ДО ЖУРНАЛУ Й ДО МОДЕЛІ (V10, Т-03) ────────
    # `обмежити_вагу` стояла в composer (ключ ранжу) і в review, а на шляху звідси
    # до моделі й журналу — ні: рядки `_доповнення_судді` (K-KOH-10 до 1.0 при
    # стелі soft 0.50) виходили як були. Тут вона один раз на верхньому рівні;
    # N образів проходять її в `знахідки_вердикту`. Ідемпотентна — двічі не ріже.
    import outfit as _O
    import реєстр_правил as _РЕЄСТР, формальність as _ФОРМ   # Н-02-01, сесія 4
    в["знахідки"] = [z for z in _РЕЄСТР.обмежити_вагу(list(в.get("знахідки") or []))
                     if not z.pop("під_підлогою", False)]
    # ── N ОБРАЗІВ З ОДНІЄЇ ВІДПОВІДІ ──────────────────────────────────────────
    # Кожен рядок «ОБРАЗ:» судиться окремо. Верхній рівень (в) лишається вердиктом
    # по ОСТАННЬОМУ — так було й так читає чинний стенд. Будується ДО стиснення
    # верхнього рівня нижче: одиничний шлях бере `основний` сирим — з `ремонт`,
    # `реєстри` й `чеклісти`, яких стиснутий рядок уже не має (Т-03).
    в["образи"] = _вердикти_образів(d, F, T, сцен, пак, _PL, основний=в,
                                    розбір=_розбір_відп)
    # ── СТРОГИЙ JSON: НЕВАЛІДНА ВІДПОВІДЬ ≠ ПОРОЖНЯ (Т-04, §1(б)) ─────────────
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ. Доти відповідь, з якої не вийшло жодного образу, і
    # відповідь, у якій модель нічого не запропонувала, виглядали для показу
    # ОДНАКОВО: порожній `образи`. Рука мовчки їхала далі без ітерацій, а в журнал
    # ішло «модель дала 0 образів» — звинувачення моделі за поломку формату.
    # Тепер розходження зі схемою називається: `відповідь_помилки` — це список
    # `{де, що}` від `протокол.перевірити`, а `повторний_виклик` — той самий список
    # JSON-ом, готовий доклеїтись до промпта (§1(б): ОДИН повторний виклик, далі
    # чесна відмова руки).
    # ЧОМУ ПОВТОРНИЙ ВИКЛИК ЛИШЕ НА НЕПРИДАТНІЙ ВІДПОВІДІ. Валідна по суті
    # відповідь без поля `версія` — робоча: образи з неї вийшли, речі резолвились,
    # судити її є чим. Просити її переписати означало б подвоїти найдорожчий виклик
    # заради поля, якого код не читає. Тому розходження їде полем ЗАВЖДИ (журнал,
    # діагноз), а повторний виклик — лише коли судити нічого.
    if d.get("текст_моделі") and not _ід_вх:
        _об_в, _чому_в = _ПР.розбір(d["текст_моделі"])
        if isinstance(_об_в, dict) and isinstance(_об_в.get("образи"), list):
            _пом_в = _ПР.перевірити(_ПР.СХЕМИ["ОБРАЗИ_V1"], _об_в)
        elif not в.get("образи") and not в.get("джерело_образу"):
            # ні JSON, ні жодного резолвленого id, і це не рука без каталогу
            _пом_в = [dict(де="корінь", що=(_чому_в or "у відповіді нема образів"))]
        else:
            _пом_в = []
        if _пом_в:
            в["відповідь_помилки"] = _пом_в[:8]
        if _пом_в and not в.get("образи") and not в.get("джерело_образу"):
            в["повторний_виклик"] = _ПР.помилка_формату(_пом_в[:8], відповідь="ОБРАЗИ_V1")
    # знахідки — лише те, що людина прочитає: суть, сила, речі; ID правила поруч
    # ПИТАННЯ — ОКРЕМО (власнику: чого бракує в каталозі), ЗНАХІДКИ — лише виміряні (моделі й журналу)
    # ── ЧЕРГА НА ВХІД — У ТІ САМІ ПИТАННЯ (Н-P12) ────────────────────────────
    # `pipeline.перевірити_від_моделі` рахує окремий список: питання, що НЕ
    # ввійшли в ключ сортування, — серед них аксесуарні «входу нема» (K-IO-03).
    # Поле `черга_на_вхід` їхало назовні й не мало жодного читача, тобто «доміряй
    # обхват зап'ястя» не доходило ні до діагнозу прогону, ні до колонки
    # `питання_коду` в журналі: код знав, чого йому бракує, і мовчав. Читач у
    # показу вже є — `в.питання`; черга стає його частиною, без повторів за
    # (правило, суть), і окремим полем далі не їде.
    _черга = в.pop("черга_на_вхід", None) or []
    в["питання"] = []
    _бач_пит = set()
    for z in [z for z in (в.get("знахідки") or []) if _PL._питання_або_нуль(z)] + list(_черга):
        _к = (z.get("правило"), str(z.get("суть"))[:120])
        if _к in _бач_пит:
            continue
        _бач_пит.add(_к)
        в["питання"].append(dict(правило=z.get("правило"), суть=z.get("суть"), речі=z.get("речі")))
    # ── АДРЕСНЕ ПИТАННЯ ЇДЕ ПЕРШИМ, А ВЖЕ ПОТІМ РІЖЕТЬСЯ СТЕЛЯ (рядок 19) ────
    # Стеля 12 і п'ятірка, яку з неї бере показ, — це те, що жінка й журнал
    # узагалі бачать із черги на вхід. Різати порядком народження знахідок
    # означало показувати те, що народилось раніше, а не те, що можна закрити:
    # `pipeline.вага_питання` ставить попереду питання з названою річчю і
    # названим полем. Сортування СТАБІЛЬНЕ — рівні за вагою лишаються в тому
    # самому порядку, що доти.
    в["питання"].sort(key=lambda z: -_PL.вага_питання(z))
    в["питання"] = в["питання"][:12]
    # ── УТРИМАНЕ РІШЕННЯ ВИХОДИТЬ ОКРЕМИМ СПИСКОМ (17.09.2026) ───────────────
    # Те саме, що вище зроблено для черги на вхід, і з тієї самої причини: поле,
    # яке нікуди не їде, невідрізненне від відсутнього. Різниця між двома
    # списками змістовна й тримається: `питання` — «доміряй ось це», `утримано` —
    # «перевірено, і саме тому нічого не стверджую». Перше — робота, друге —
    # ухвалене рішення, і плутати їх означало б показувати жінці чергу там, де
    # черги нема.
    в["утримано"] = [dict(правило=z.get("правило"), суть=z.get("суть"), речі=z.get("речі"))
                     for z in (в.pop("утримано", None) or [])][:8]
    # ── K-SIG-01 І РЕШТА АНТИ-ПРАВИЛ НАД ВЛАСНОЮ МОВОЮ КОДУ ──────────────────
    # Те саме рішення, що двома рядками вище: поле, яке нікуди не їде, не
    # відрізнити від відсутнього. Тут воно ще й про САМУ СИСТЕМУ: чи не порушує
    # заборонених формул той текст, який пише код, а не модель. Чисто — це вимір,
    # а не тиша, тож `чисто` виходить завжди, з лічбою перевіреного.
    _мгк = в.pop("мовний_гейт_коду", None) or {}
    # ── ДВА ІМЕНІ НА ОДНЕ ПОЛЕ (знайдено аудитом контрактів 19.09.2026) ──────
    # Писар — `language_gate.перевірити_знахідки` — віддає список брудних під
    # ключем `деталі` (`dict(усього=…, брудних=…, деталі=брудні, чисто=…)`).
    # Читалось тут `_мгк.get("брудні")`, тобто ключ, якого в тому словнику нема
    # НІКОЛИ. Наслідок був не виняток, а ГІРШЕ: `.get` мовчки давав None, і
    # `чисто` виходило `True`, а `брудних` — 0 НА БУДЬ-ЯКОМУ ВХОДІ. K-SIG-01 і
    # решта анти-правил над власною мовою коду звітували жінці «чисто» навіть
    # тоді, коли гейт щойно нарахував порушення: «промовчало правильно» й
    # «спрацювало, але вивід загубив» лишали однаковий слід — рівно та хвороба,
    # проти якої цей вихід і додавався (коментар нижче по `pipeline`).
    # Лічба й вердикт тепер беруться в писаря готовими, а не перераховуються з
    # другого імені: одне поле — одне джерело.
    _брудні = _мгк.get("деталі") or []
    в["мовний_гейт_коду"] = dict(
        чисто=_мгк.get("чисто", not _брудні),
        брудних=_мгк.get("брудних", len(_брудні)),
        правила=[dict(правило=x.get("правило"),
                      порушення=[y.get("правило") for y in
                                 ((x.get("вердикт") or {}).get("порушення") or [])])
                 for x in _брудні][:6])
    в["знахідки"] = [z for z in (в.get("знахідки") or []) if not _PL._питання_або_нуль(z)]
    в["знахідки"] = [dict(правило=z.get("правило"), сила=z.get("сила"), сила_нп=z.get("сила_нп"),
                          суть=z.get("суть"), речі=z.get("речі"), регістр=z.get("регістр"),
                          **({"свідомий": z["свідомий"]} if z.get("свідомий") else {}))
                     for z in (в.get("знахідки") or [])[:12]]
    в["граф"] = dict(вузли=(в["граф"] or {}).get("вузли"), ребер=len((в["граф"] or {}).get("ребра") or []))
    # ── МОВНИЙ ЦИКЛ НАЗОВНІ ПОЛЯМИ (Т-07) ────────────────────────────────────
    # ТУТ, А НЕ В `if в["образи"]` НИЖЧЕ: крок опису й вибору приходять сюди вже
    # `ід`, тобто без образів у відповіді, а руки 3/4 не мають їх за побудовою —
    # і саме там текст читає жінка. У попередній гілці поле не дісталось би нікому,
    # кому воно потрібне.
    # ХТО РАХУЄ СПРОБИ. Скільком переписам цей текст уже підданий, знає лише
    # викликач: показ шле `мова_спроба` (1 — те, що модель написала сама). Без неї
    # це перша спроба — так приходять гейти, стенд і тест живого шляху, і вони
    # поля не читають.
    # ДВА ПОЛЯ, БО ДВА РІЗНІ ПИТАННЯ: `мова_повтор` — «проси перепис» (з промптом
    # `промпт_мови`, уже без кодів правил, як промпт ремонту); `мова_рішення` —
    # «що робити, якщо цей текст фінальний» (Р-2). Друге стоїть при КОЖНОМУ
    # брудному тексті, а не лише після останньої спроби: показ приймає перепис
    # лише коли той чистіший, тож фінальним може лишитись і текст першої спроби.
    try:
        _мсп = max(1, int(d.get("мова_спроба") or 1))
    except (TypeError, ValueError):
        _мсп = 1
    _мповтор = _PL.мова_повтор(в.get("мова"), спроба=_мсп, відповідь=_відп_схема)
    if _мповтор:
        в["мова_повтор"] = _мповтор
        в["промпт_мови"] = _json.dumps(_вердикт_для_моделі(_мповтор),
                                       ensure_ascii=False, separators=(",", ":"))
    _мріш = _PL.мова_рішення(в.get("мова"), спроб=_мсп - 1)
    if _мріш:
        в["мова_рішення"] = _мріш
    if d.get("_розбір_блоків"):
        в["розбір_блоків"] = d.pop("_розбір_блоків")
    # ── ЦИКЛ: НАСТУПНИЙ ПРОМПТ БУДУЄ КОД, А НЕ JS ────────────────────────────
    # ЩО ЦЕ МІНЯЄ. `pipeline.промпт_ремонту` і `промпт_вибору` існували з 30.08 і
    # НЕ КЛИКАЛИСЬ НІКИМ — мертві гілки за означенням проєкту (виконується, лишає
    # слід, міняє рішення: перших двох не було). Причина була механічна: стенд
    # говорить із Python лише через `виклик`, а віддавати туди не було чого.
    # Тепер вердикти й наступний промпт приїжджають одним пакетом, тож ітерація
    # коштує стенду один рядок JS, а не власну збірку промпта на боці інтерфейсу
    # (де вона розійшлася б із форматом розбору вже на першій правці).
    # ЧОМУ ОБИДВА ОДРАЗУ. Вони будуються з уже порахованого `образи` — це склейка
    # рядків, не обчислення; вибір «ремонт чи вибір» лишається за стендом, і код
    # не мусить знати, котра це ітерація.
    # З Т-03 промпт ремонту — це ОБʼЄКТ `ВЕРДИКТ_V1` (`в["вердикт"]`), і показ дістає
    # обидва: обʼєкт для журналу й той самий обʼєкт рядком для моделі. Промпти
    # вибору лишаються прозою до Т-06.
    if в["образи"]:
        _вип = d.get("випадок")
        _рем = int(d.get("ремонт_варіантів") or 2)
        # ── ЗАПИТ РЕЧІ СЛОВАМИ (05.09.2026) — ПЕРЕД ВЕРДИКТОМ (Т-03) ──────────
        # модель сказала «потрібно: …» — код шукає по всьому каталогу під жорсткими
        # відсіченнями, кладе знахідки в пул (номери їм роздаються ПІСЛЯ наявних,
        # тож нумерація образів не зсувається) і показує їх у «вітрина» вердикту.
        # Без цього право ші на річ поза пулом порожнє.
        _потрібно = _PL.запити_речей_з_тексту(d.get("текст_моделі"))
        в["запропоновано"] = []
        if _потрібно:
            _пасп = d.get("паспорт") if isinstance(d.get("паспорт"), dict) else {}
            for _фраза in _потрібно:
                _зн = _PL.шукати_словами(пак["_каталог"], _фраза, n=4, темп_c=сцен.get("темп_c"), вето=_пасп.get("вето"))
                for _r in _зн:
                    _сл = _r.get("слот")
                    if _сл in пак["кандидати"] and all(x.get("id") != _r.get("id") for x in пак["кандидати"][_сл]):
                        пак["кандидати"][_сл].append(dict(_r, за_запитом=_фраза))
                    в["запропоновано"].append(dict(id=_r.get("id"), назва=str(_r.get("назва") or "")[:60], слот=_сл, запит=_фраза))
        # ── ВЕРДИКТ — ОДИН ОБʼЄКТ, ПРОМПТ — ТОЙ САМИЙ ОБʼЄКТ (Т-03) ────────────
        # ВІТРИНА ЇДЕ З ТОГО САМОГО ПАКЕТА, ЩО ЙШОВ У ПЕРШУ ІТЕРАЦІЮ: кандидати
        # вже пораховані, зрізані бюджетом і спаковані — другого відбору не треба.
        # ── ІТЕРАЦІЯ ПРИХОДИТЬ ВІД ПОКАЗУ (Т-04 обіцяв, Т-06 вимагає) ─────────
        # ЩО ЦЕ МІНЯЄ. Доти `ітерація` не приходила нізвідки, тож КОЖЕН вердикт
        # живого шляху називався першим — і перевірка виконання правок (Т-05)
        # стояла готова, але не вмикалась НІКОЛИ: без попереднього вердикта вона
        # мовчить за побудовою. Т-06 без цього теж не тримається: його крок 1
        # каже «виклик 3 дістає вердикт ІТЕРАЦІЇ 2», а вердикт, який зветься
        # першим, тією ітерацією не є. `відповідь_моделі` розбирається тут, бо
        # показ шле текст, а `перевірити_виконання` читає поле `виконано` обʼєкта.
        _іт = d.get("ітерація") or 1
        _поперед = (d.get("попередній_вердикт")
                    if isinstance(d.get("попередній_вердикт"), dict) else None)
        _відп_об = (_ПР.розібрати_json(d["текст_моделі"])
                    if (_поперед and d.get("текст_моделі")) else None)
        в["вердикт"] = _PL.вердикт_v1(в["образи"], варіантів=_рем, випадок=_вип,
                                       кандидати=пак.get("кандидати"),
                                       ітерація=_іт,
                                       попередній_вердикт=_поперед,
                                       відповідь_моделі=_відп_об,
                                       мова=в.get("мова"), реєстри=в.get("реєстри"))
        # РОЗХОДЖЕННЯ ЗІ СХЕМОЮ — НАЗОВНІ ПОЛЕМ, не в тишу (як `протокол_помилки`
        # у `запити`, Т-02): вердикт їде, а розходження їде поруч; читає його
        # `тест_живого_шляху`. Відмову руки на невалідній ВІДПОВІДІ вводить Т-04.
        _пом = _ПР.перевірити(_ПР.СХЕМИ["ВЕРДИКТ_V1"], в["вердикт"])
        if _пом:
            в["протокол_помилки"] = _пом
        в["промпт_ремонту"] = _json.dumps(_вердикт_для_моделі(в["вердикт"]),
                                          ensure_ascii=False, separators=(",", ":"))
        в["промпт_вибору"] = _без_ід_рядків(_PL.промпт_вибору(в["образи"], випадок=_вип,
                                                              без_фото=bool(d.get("без_фото"))))
        # ── ВИКЛИК 3 — ТОЙ САМИЙ ВЕРДИКТ, ІНШЕ ЗАВДАННЯ (Т-06, крок 1) ────────
        # `вибір_над` їде назовні обʼєктом і повертається сюди тим самим полем на
        # наступному виклику: вибір звіряється проти того, що код САМ сказав
        # моделі, а не проти нового набору образів. Промпт — той самий обʼєкт без
        # кодів правил, як і промпт ремонту.
        в["вибір_над"] = _PL.вердикт_вибору(в["вердикт"])
        в["промпт_лише_вибору"] = _json.dumps(_вердикт_для_моделі(в["вибір_над"]),
                                              ensure_ascii=False, separators=(",", ":"))
        # ── ПОВНОТА — РІШЕННЯ КОДУ, А НЕ ГЕЙТ У JS (18.09.2026) ───────────────
        # `повнота` каже показу, що з ЦЬОГО вердикта можна віддати жінці: образ,
        # який код приймає, або — коли такого нема — найповніший із неповних разом
        # із чесним рядком для картки. Доти показ брав `в.речі` (верхній рівень —
        # ОСТАННІЙ образ відповіді) і гейт `length >= 2`, тож образ на три речі без
        # сумки їхав на картку мовчки.
        # `промпт_повноти` — ЗАЙВІ ВИКЛИКИ НА РУКУ, і їх щонайбільше
        # `спроб_повноти`: показ каже номером, котра спроба вже позаду
        # (`спроба_повноти`), Python вирішує решту — текст другої спроби
        # (адресний) і, коли спроби вичерпані, ДОБІР КОДОМ (власник, 19.09.2026).
        _сп_пвн = int(d.get("спроба_повноти") or 0)
        _добір = _сп_пвн >= _РЕЄСТР.C["спроб_повноти"]
        в["повнота"] = _PL.повнота_набору(в["вердикт"], кандидати=пак["кандидати"],
                                          каталог=пак["_каталог"], сценарій=сцен,
                                          дібрати=_добір,
                                          запасний=(_поперед if _сп_пвн else None))
        # ВІДПОВІДЬ РЕМОНТУ, ЯКА НЕ РОЗІБРАЛАСЬ, ТЕЖ ВИТРАЧАЄ СПРОБУ, але не
        # мусить забирати НАСТУПНУ: промпт наступної спроби будується тоді з
        # попереднього вердикта — того самого, який і піде на картку.
        _база_пвн = (в["вердикт"] if (в["вердикт"] or {}).get("образи")
                     else (_поперед or в["вердикт"]))
        _пвн = _PL.вердикт_повноти(_база_пвн, спроба=_сп_пвн + 1)
        if _пвн is not None and not (в["повнота"] or {}).get("повний") and not _добір:
            в["промпт_повноти"] = _json.dumps(_вердикт_для_моделі(_пвн),
                                              ensure_ascii=False, separators=(",", ":"))
    # ── ГЕЙТ ВИБОРУ Й ВІДПОВІДЬ ОПИСУ — ПОЛЯМИ НАЗОВНІ (Т-06) ────────────────
    # Доти «вибір приймається лише з ≥2 речами й без структурного блокера» стояло
    # в JS регуляркою по словах рядка `блокує`, а «ФОТО НЕ ТЕ: N» вирізалось із
    # прози другою регуляркою з власною нумерацією фото. Обидва рішення тепер тут,
    # і показ читає готові поля: `вибір` (що обрано, що прибрано, чим замінено і
    # чому) та `опис` (проза, поради, речі з чужим фото).
    if _вибір is not None:
        в["вибір"] = _вибір
        if not _вибір["ід"]:
            в["перевірено"] = False
            в["чому"] = (_вибір.get("чому_відмова")
                         or "вибір не прочитано й запасного образу без блокера немає")
    if _опис_відп is not None:
        в["опис"] = _опис_відп
    # ── K-VAR-01 БАЧИТЬ ПОВТОР МІЖ КАРТКАМИ ОДНОГО ПРОГОНУ (рядок 48, 19.09) ──
    # `pipeline.різноманітність` (вище, у `вердикт_v1`) судить лише 10 варіантів
    # ОДНІЄЇ руки — вердикти рук 1 і 2 одне одного не бачать за побудовою, тож
    # «той самий клатч у двох картках» K-VAR-01 доти не міг спіймати НІКОЛИ.
    # `_ОБРАНО_ПРОГОНУ` — пам'ять ОДНОГО прогону (сирий `сід`, спільний на всі
    # руки): кожен виклик, у якому `перевірити_від_моделі` резолвила бодай одну
    # річ, кладе туди СКЛАД СВОЄЇ КАРТКИ й читає чужий. Ключ — СИРИЙ сід, а не
    # `_сід_руки`: сіль руки 2 (PR #92) міняє лише порядок рівних усередині
    # пулу, а прогін лишається один.
    # ── СУДИТЬСЯ КАРТКА, А НЕ ПЕРЕБІР (рядок 70, 19.09.2026) ─────────────────
    # Блок стояв вище — там, де `повнота` ще не порахована, — і діставав
    # `в["речі"]`: верхній рівень вердикта, тобто ОСТАННІЙ образ відповіді
    # (о10 з десяти на ітерації 1, о5 з п'яти на ітерації 2). До жінки той
    # образ не їде: що піде на картку, вирішує `повнота_набору` нижче по
    # файлу, і показ бере саме `повнота.ід` (`показ.html`: «СКЛАД КАРТКИ — ТОЙ
    # САМИЙ, ЩО ПІШОВ В ОПИС»). Тому блок переїхав СЮДИ, за `повнота`, і бере
    # її рішення; `в["речі"]` лишається запасним — для рук 3–4 (без каталогу)
    # і для шляхів, де вердикта, а отже й повноти, нема.
    # ЩО ЦЕ ЗМІНИЛО, ЧИСЛОМ (`проби/povtor_remont_70.py`, сіди стенда 7 і 11):
    # до — 2 повтори з 2 сідів, обидва на сумці, і обидва на образі, якого на
    # картці нема (картки рук 1 і 2 несли РІЗНІ сумки); після — 0 з 2.
    if d.get("сід"):
        _ід_картки = set((в.get("повнота") or {}).get("ід") or [])
        _картка = [r for r in (в.get("речі") or []) if r.get("id") in _ід_картки] \
            if _ід_картки else (в.get("речі") or [])
        if _картка:
            _пвт = _PL.повтор_прогону(_ОБРАНО_ПРОГОНУ.setdefault(int(d["сід"]), {}),
                                      ("2" if _рука_2 else "1"), _картка)
            if _пвт:
                в["k_var_01_прогону"] = _пвт
    в["слід_правил"] = СЛ.зібрати()
    # ── ПАЛІТРА ЦІЄЇ РУКИ — ФАКТОМ, А НЕ ЗДОГАДОМ (01.09.2026) ──────────────
    # Вимога власника: «абсолютно всі дії людини і кожної руки мають
    # записуватися». Без цього блоку вердикт не відрізняє три різні речі:
    # людина обрала схему; людина сказала «хай вирішує ші»; людина не бачила
    # вибору взагалі (стара збірка). «Носитиму» на них означає різне.
    # ЧОМУ ПО РУЦІ, А НЕ ПО ПРОГОНУ. Індекс гілки — це РАНГ у розвилці, а
    # розвилка рахується з колориту: рука 1 і рука 2 (донор) на тому самому
    # ранзі дістають РІЗНІ схеми (виміряно 01.09: ранг 0 → «нейтрали+акцент»
    # у руки 1 і «тональна» у руки 2). Одне поле на прогін тут збрехало б.
    _вк = d.get("вибір_кольору") or {}
    в["палітра"] = dict(
        схема=("—" if гілка is None else п["палітри"]["розвилка"][гілка]["схема"]),
        схема_обрана=(гілка is not None), гілка=гілка,
        схем_у_розвилці=len(п["палітри"]["розвилка"]),
        база=_вк.get("база"), база_обрана=bool(_вк.get("база")),
        насиченість=_вк.get("насиченість"),
        насиченість_обрана=bool(_вк.get("насиченість")),
        донор=_донор,
        # що САМЕ зламано в руці 2 — у журнал вердикту, а не «донор так/ні» навмання
        поломки=sorted(_поломки_2),
        # …і ЩО ЦЕ ЗМІНИЛО (Т-11 крок 2): journal читає рядок, не здогад
        поломка=(_поломка_2 if _рука_2 else None))
    в.setdefault("перевірено", True)
    return _json.dumps(в, ensure_ascii=False, default=str)


