    _дріт_р = _Д.вердикт(_на_дріт(в, вердикт_для_моделі(в["вердикт"]), "промпт_ремонту", _сід_р, "repair",
                                  образи=True))
    _дріт_р["case"] = _випадок_кодами(пак, _дріт_р)
    в["промпт_ремонту"] = _json.dumps(
        _ЗП.зібрати(_P.оголошення_ремонту(_дріт_р), _дріт_р, мова_тексту=d.get("мова_тексту")),
        ensure_ascii=False, separators=(",", ":"))
