def _факти_заяви(з):
    """Ключі фактів заяви: (клас, id речі) для кожної названої речі; заява без речі — (клас, значення)."""
    клас = _ФАКТ_ЗАЯВИ.get(з.get("code"), з.get("code"))
    в = з.get("values") or {}
    речі = [х.get("item_id") for х in в.get("items") or [] if isinstance(х, dict) and х.get("item_id")]
    речі += [і for і in [в.get("item_id"), (в.get("item") or {}).get("item_id") if isinstance(в.get("item"), dict)
                         else None] if і]
    return ({(клас, і) for і in речі} if речі
            else {(клас, _json.dumps(в, sort_keys=True, ensure_ascii=False))})


def _лише_її(пункти):
    """Залишає в повідомленнях картки її заяви й показує кожен факт лише раз."""
    бачено, вих = set(), []
    for п in пункти:
        заяви = (п.get("повідомлення") or {}).get("statements") or []
        if п.get("для_всіх") or not заяви:
            вих.append(п)
            continue
        її = []
        for з in заяви:
            нові = _факти_заяви(з) - бачено
            if з.get("recipient") not in _НЕ_ЖІНЦІ and нові:
                бачено |= нові
                її.append(з)
        if len(її) == len(заяви):
            вих.append(п)
            continue
        складові = п.get("складові") or [dict(правило=п.get("правило"), повідомлення=п["повідомлення"])]
        п = {к: в for к, в in п.items() if not (к == "на_розгортання" and not її)}
        вих.append(dict(п, складові=складові, **(dict(повідомлення=_ВМ_в.повідомлення("card_unchecked", *її))
                                                 if її else dict(для_всіх=1))))
    return вих
