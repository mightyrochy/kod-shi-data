    _вс = _ВП.для_суду(d)
    сцен["вибір_схеми"] = _вс
    сцен["розмова_шаром"] = _ПН.розмова_для_суду(d.get("паспорт"))
    return _ПН.сценарій_з(сцен, d.get("паспорт")), _вс


