# ─────────────────────────── Lab ↔ RGB (робочий простір) ───────────────────
SPACES = {"sRGB":((.4124,.3576,.1805,.2126,.7152,.0722,.0193,.1192,.9505),),
          "P3":  ((.4866,.2657,.1982,.2290,.6917,.0793,.0000,.0451,1.0439),)}
def _f(t):  return t**(1/3) if t > 216/24389 else (841/108)*t + 4/29
def _fi(t): return t**3 if t**3 > 216/24389 else (t-4/29)*108/841
def to_lab(rgb, space="sRGB"):
    m=SPACES[space][0]; r,g,b=[c/255 for c in rgb]
    r,g,b=[((c+.055)/1.055)**2.4 if c>.04045 else c/12.92 for c in (r,g,b)]
    X,Y,Z=(r*m[0]+g*m[1]+b*m[2], r*m[3]+g*m[4]+b*m[5], r*m[6]+g*m[7]+b*m[8])
    fx,fy,fz=_f(X/.95047),_f(Y),_f(Z/1.08883)
    return (116*fy-16, 500*(fx-fy), 200*(fy-fz))
def _inv(space):
    a,b,c,d,e,f,g,h,i=SPACES[space][0]; det=a*(e*i-f*h)-b*(d*i-f*g)+c*(d*h-e*g)
    return [[(e*i-f*h)/det,(c*h-b*i)/det,(b*f-c*e)/det],
            [(f*g-d*i)/det,(a*i-c*g)/det,(c*d-a*f)/det],
            [(d*h-e*g)/det,(b*g-a*h)/det,(a*e-b*d)/det]]
def to_rgb(L,a,b,space="sRGB"):
    fy=(L+16)/116; X,Y,Z=.95047*_fi(fy+a/500), _fi(fy), 1.08883*_fi(fy-b/200)
    M=_inv(space); lin=[M[i][0]*X+M[i][1]*Y+M[i][2]*Z for i in range(3)]
    return [1.055*c**(1/2.4)-.055 if c>.0031308 else 12.92*c for c in lin]

def hex_з_lab(lab, space="sRGB"):
    """`#rrggbb` з Lab — ОДНА точка перетворення для рис, смуг і дуг.

    Поза гамутом простору канал обрізається до [0,1]: це ЗОБРАЖЕННЯ кольору для
    екрана, а не твердження, що колір відтворюваний. Стеля реальної поверхні —
    окреме питання і живе в `c_max_поверхня` (R-COL-12); змішувати їх не можна:
    перше каже «як це показати», друге — «чи буває така тканина».
    """
    return "#%02x%02x%02x" % tuple(
        int(round(max(0.0, min(1.0, c)) * 255)) for c in to_rgb(*lab, space=space))

def to_xyz(lab):
    L,a,b = lab; fy=(L+16)/116
    return (.95047*_fi(fy+a/500), _fi(fy), 1.08883*_fi(fy-b/200))

def from_xyz(X,Y,Z):
    fx,fy,fz=_f(X/.95047),_f(Y),_f(Z/1.08883)
    return (116*fy-16, 500*(fx-fy), 200*(fy-fz))

# ───────────────────────── OKLab: ПАЛІТРНИЙ МАСШТАБ ─────────────────────────
# ЧОМУ ВІН З'ЯВИВСЯ, І ЧОМУ САМЕ ЗАРАЗ (before/after на реальному рішенні).
# Корпус (тема-2) ще торік записав рішення НЕ як міграцію, а як РОЗДІЛЕННЯ:
# «ΔE00 надійний для малих різниць (<~5) … для палітрного масштабу L*C*h /
# OKLab; CIEDE2000 лишити для строгого match-tolerance». Рішення не було
# імплементоване: в коді 0 рядків OKLab, усі відстані — de00.
#
# ЩО ВИМІРЯНО, коли це нарешті перевірили числом:
#  · на 28 реальних кольорах каталогу 2.94% трійок ПОРУШУЮТЬ нерівність
#    трикутника, і найгірший випадок — найбанальніший образ, який існує:
#    чорний→молочний = 84.6, а через сірий = 38.9+27.4 = 66.3;
#  · медіана попарної ΔE00 у реальному образі = 35.9, і лише 0.3% пар лежать
#    у діапазоні ≤5, на якому CIEDE2000 підганяли.
# Отже координація.середня_близькість() УСЕРЕДНЮВАЛА величину, яка на її
# робочому масштабі не є метрикою. Усереднення попарних відстаней вимагає
# метричності; ΔE00 її не дає й не обіцяє — вона попарна ОЦІНКА, не простір.
#
# ДЕ ЛАМАЄТЬСЯ OKLab. Він рівномірніший для великих різниць і є справжнім
# евклідовим простором (тож усереднення й кластеризація законні), АЛЕ на малих
# різницях він гірший за CIEDE2000 і не має промислових допусків. Тому
# de00 ЛИШАЄТЬСЯ там, де питання «та сама річ чи інша» (verify, feed, свотчі),
# а OKLab бере палітрний масштаб. Це не заміна, це розділення за масштабом.
_OK_M1 = ((0.8189330101, 0.3618667424, -0.1288597137),
          (0.0329845436, 0.9293118715,  0.0361456387),
          (0.0482003018, 0.2643662691,  0.6338517070))
_OK_M2 = ((0.2104542553,  0.7936177850, -0.0040720468),
          (1.9779984951, -2.4285922050,  0.4505937099),
          (0.0259040371,  0.7827717662, -0.8086757660))

# R-COL-08 — дубль `colorspace.to_oklab`: OKLab для кластеризації й інтерполяції.
def to_oklab(lab):
    """CIELAB (D65) → OKLab (Ottosson 2020, база CSS Color 4).
    Вхід — той самий Lab, що всюди в модулі, тож жоден виклик не мусить знати
    про XYZ."""
    X, Y, Z = to_xyz(lab)
    lms = [m[0]*X + m[1]*Y + m[2]*Z for m in _OK_M1]
    lms = [(v ** (1/3)) if v >= 0 else -((-v) ** (1/3)) for v in lms]
    return tuple(m[0]*lms[0] + m[1]*lms[1] + m[2]*lms[2] for m in _OK_M2)

# R-COL-07 — дубль `colorspace.d_ok`: ΔE00 неметрична, палітрний масштаб рахує окрема міра.
def d_ok(lab1, lab2):
    """Евклідова відстань у OKLab — ПАЛІТРНИЙ масштаб.

    КОЛИ ДІЯТИ: коли треба усереднити, кластеризувати чи ранжувати кілька
    кольорів разом (координація образу, побудова палітри).
    НАСКІЛЬКИ: це справжня метрика — нерівність трикутника виконується завжди,
    тож середнє й центроїд визначені.
    ДЕ ВІДМОВЛЯЄ: на малих різницях (питання «той самий колір?») — там de00.
    Шкала ІНША, ніж у ΔE00: числа не порівнювати між метриками, лише всередині."""
    a, b = to_oklab(lab1), to_oklab(lab2)
    return ((a[0]-b[0])**2 + (a[1]-b[1])**2 + (a[2]-b[2])**2) ** 0.5

def адаптувати(еталон_до, еталон_після):
    """Зведення кадру до світла іншого кадру за спільною поверхнею (зазвичай шкіра).

    ЧОМУ НЕ АДИТИВНИЙ ЗСУВ У LAB. Зміна освітлення множить сигнал: удвічі тьмяніше
    світло дає вдвічі менше випромінення від КОЖНОЇ поверхні. У L* це стиснення до
    нуля, а не віднімання сталої. Зсув, узятий зі шкіри (L*≈66), при накладанні на
    чорний светр (L*10) дає L*−2 — за межею шкали, — а сірий переводить в іншу
    сім'ю. Перевірено на реальному зсуві ΔE00=9.4: усі речі отримували −12.5 L*
    незалежно від власної світлоти.
    Правильно — діагональне масштабування в XYZ (фон Кріс): коефіцієнт береться з
    еталонної поверхні й множить, а не віднімає. Це стандартна хроматична адаптація,
    а не моя евристика; T1 за формою, хоча вибір шкіри за еталон — T3."""
    Xa,Ya,Za = to_xyz(еталон_до); Xb,Yb,Zb = to_xyz(еталон_після)
    k = (Xa/Xb if Xb > 1e-9 else 1.0, Ya/Yb if Yb > 1e-9 else 1.0, Za/Zb if Zb > 1e-9 else 1.0)
    def адаптер(lab):
        X,Y,Z = to_xyz(lab)
        return from_xyz(X*k[0], Y*k[1], Z*k[2])
    return адаптер, dict(коефіцієнти=[round(x,3) for x in k],
                         зсув_de00=round(de00(еталон_до, еталон_після),1))

# ── R-MUN-07: ЗМІНА ОСВІТЛЮВАЧА (C → D65) — НЕ ТЕ САМЕ, ЩО ЗВЕДЕННЯ КАДРІВ ───
# Pointer 1980 і реннотація Munsell задані під освітлювачем C; весь модуль рахує
# Lab під D65 (`to_xyz`/`from_xyz`: 0.95047/1.08883). Звіряти C*-стелю з-під C із
# кольором з-під D65 — систематична похибка по всьому шару гамуту (тема-2,
# R-MUN-07: «the mismatch is systematic across the whole gamut layer»).
# ЧОМУ НЕ `адаптувати` ВИЩЕ. Вона діагональна в XYZ, і для зміни освітлювача така
# діагональ — ТОТОЖНІСТЬ у Lab за побудовою: CIELAB уже нормує кожну вісь XYZ на
# свій білий, тож масштабування XYZ під новий білий скорочується з нормуванням.
# Виміряно 19.09.2026 на 8 вузлах корпусу: зсув C* = 0.00 на всіх восьми
# (`метод="XYZ"` нижче лишено саме для того, щоб це перевіряла проба, а не коментар).
# «Адаптувати наявним адаптером» дало б ті самі числа під новим іменем.
# Тому тут — фон Кріс у КОНУСНОМУ просторі (Bradford, T1: Lam 1985; ICC.1:2004-10
# Annex E): масштабування діагональне в LMS, не в XYZ, і воно числа змінює.
# Виміряно на 576 вузлах Pointer (C→D65, Bradford): ΔL* −0.50…+0.24, Δh° −3.35…+0.44
# (середнє |Δh| 0.99°), ΔC* −1.14…+2.88 (середнє |ΔC*| 0.90; відносно −1.0 %…+5.1 %).
# Зсув малий, але систематичний — і тепер він у числах, а не в застереженні.
БІЛІ = {"D65": (0.95047, 1.0, 1.08883),          # той самий білий, що в to_xyz/from_xyz
        "C":   REGISTRY["illum_C"]["val"]}
_BRADFORD = (( 0.8951,  0.2664, -0.1614),
             (-0.7502,  1.7135,  0.0367),
             ( 0.0389, -0.0685,  1.0296))
def _множ(m, v):
    return tuple(m[r][0]*v[0] + m[r][1]*v[1] + m[r][2]*v[2] for r in range(3))
def _обернена_3x3(m):
    (a,b,c),(d,e,f),(g,h,i) = m
    det = a*(e*i-f*h) - b*(d*i-f*g) + c*(d*h-e*g)
    return (((e*i-f*h)/det, (c*h-b*i)/det, (b*f-c*e)/det),
            ((f*g-d*i)/det, (a*i-c*g)/det, (c*d-a*f)/det),
            ((d*h-e*g)/det, (b*g-a*h)/det, (a*e-b*d)/det))
_BRADFORD_ОБЕРНЕНА = _обернена_3x3(_BRADFORD)   # рахується, а не переписується: без друкарських помилок

def адаптувати_освітлювач(lab, від="C", до="D65", метод="Bradford"):
    """Lab під освітлювачем `від` → Lab під `до` (D65 — простір модуля).

    метод="Bradford" — фон Кріс у LMS (T1, REGISTRY['cat_bradford']).
    метод="XYZ" — діагональ у XYZ, форма `адаптувати`: лишена, щоб тотожність
    (зсув 0.00 у Lab) можна було ПЕРЕВІРИТИ пробою, а не вірити коментарю."""
    Wa, Wb = БІЛІ[від], БІЛІ[до]
    L, a, b = lab; fy = (L + 16) / 116
    xyz = (Wa[0]*_fi(fy + a/500), _fi(fy), Wa[2]*_fi(fy - b/200))   # білий ДЖЕРЕЛА, не D65
    if метод == "XYZ":
        xyz = tuple(xyz[i] * Wb[i] / Wa[i] for i in range(3))
    else:
        la, lb = _множ(_BRADFORD, Wa), _множ(_BRADFORD, Wb)
        lms = _множ(_BRADFORD, xyz)
        xyz = _множ(_BRADFORD_ОБЕРНЕНА, tuple(lms[i] * lb[i] / la[i] for i in range(3)))
    fx, fy, fz = _f(xyz[0]/Wb[0]), _f(xyz[1]/Wb[1]), _f(xyz[2]/Wb[2])
    return (116*fy - 16, 500*(fx - fy), 200*(fy - fz))

# R-COL-03 — дубль `colorspace.lch`: L*C*h як інтерпретована трійка над Lab.
def lch(lab):
    L,a,b=lab; return L, math.hypot(a,b), math.degrees(math.atan2(b,a))%360
def hx(s): return to_lab(tuple(int(s.lstrip('#')[i:i+2],16) for i in (0,2,4)))

# ─────────────────────────── ΔE00 (звірено з Sharma 2005) ──────────────────
# R-COL-01 — дубль `colorspace.de00`: перцептивний простір замість sRGB (реєстр `rule_genus`).
def de00(lab1, lab2, kL=1, kC=1, kH=1):
    L1,a1,b1=lab1; L2,a2,b2=lab2
    C1,C2=math.hypot(a1,b1),math.hypot(a2,b2); Cb=(C1+C2)/2
    G=.5*(1-math.sqrt(Cb**7/(Cb**7+25**7))) if Cb>0 else .5
    a1p,a2p=(1+G)*a1,(1+G)*a2
    C1p,C2p=math.hypot(a1p,b1),math.hypot(a2p,b2)
    h1p=math.degrees(math.atan2(b1,a1p))%360; h2p=math.degrees(math.atan2(b2,a2p))%360
    dLp=L2-L1; dCp=C2p-C1p
    if C1p*C2p==0: dhp=0
    else:
        dhp=h2p-h1p; dhp-=360 if dhp>180 else (-360 if dhp<-180 else 0)
    dHp=2*math.sqrt(C1p*C2p)*math.sin(math.radians(dhp)/2)
    Lbp=(L1+L2)/2; Cbp=(C1p+C2p)/2
    if C1p*C2p==0: hbp=h1p+h2p
    elif abs(h1p-h2p)<=180: hbp=(h1p+h2p)/2
    else: hbp=(h1p+h2p+360)/2 if h1p+h2p<360 else (h1p+h2p-360)/2
    T=(1-.17*math.cos(math.radians(hbp-30))+.24*math.cos(math.radians(2*hbp))
       +.32*math.cos(math.radians(3*hbp+6))-.20*math.cos(math.radians(4*hbp-63)))
    SL=1+(.015*(Lbp-50)**2)/math.sqrt(20+(Lbp-50)**2); SC=1+.045*Cbp; SH=1+.015*Cbp*T
    RT=-math.sin(math.radians(60*math.exp(-((hbp-275)/25)**2)))*2*math.sqrt(Cbp**7/(Cbp**7+25**7))
    return math.sqrt((dLp/(kL*SL))**2+(dCp/(kC*SC))**2+(dHp/(kH*SH))**2
                     +RT*(dCp/(kC*SC))*(dHp/(kH*SH)))

def soft(x, lo, hi, w):
    return 1/(1+math.exp(-(x-lo)/w)) * 1/(1+math.exp((x-hi)/w))

# ── R-COL-11: тканина міряється CIEDE2000(2:1:1), не (1:1:1) ────────────────
# Тема-2, R-COL-11 · T2 · default. На текстурованій поверхні різниці СВІТЛОТИ
# перцептивно знецінюються; текстильна форма формули — kL=2. Умова kL=1 (референс)
# передбачає пласкі однорідні зразки.
# Родовід: лінія ISO 105-J03; підтверджено на 108 парах пряжофарбованих тканин,
# 13 спостерігачів, три освітлювачі — там CIEDE2000(2:1:1) обійшла альтернативи.
#
# ВИМІРЯНО НА БАЗОВОМУ ГАРДЕРОБІ (16 кольорів, 120 пар, гейт tone-on-tone ΔE00<6):
# середня ΔE00 падає 35.8 → 24.2 (стиснення 32%); перевертаються ТРИ пари —
# графіт+чорний 11.13→5.56, білий+світло-сірий 11.08→5.81, олива+хакі 9.10→4.93.
# Усі три — нейтралі, рознесені переважно по L*, тобто рівно та вісь, якої торкається
# kL, і рівно ті пари, заради яких гейт існує. Частка перевертань (2.5%) применшує
# наслідок: важливо не скільки, а ЯКІ.
#
# ⚠ ЦЕЙ ПЕРЕВОРОТ ТУТ НЕ ВІДТВОРЕНО. Тих 16 кольорів у кодовій базі НЕМАЄ — вони жили
# в дослідницькій сесії теми-2. Числа вище ЗАПОЗИЧЕНІ, і лишаються передбаченням:
# щойно базовий гардероб з'явиться в коді як список Lab, прогнати 120 пар і звірити,
# що перевертаються рівно ці три й жодна не йде назад. Перевернеться четверта —
# константа живе не там, де вважає R-COL-11.
#
# ДЕ ЛАМАЄТЬСЯ, І ЦЕ НЕ ДРІБНИЦЯ: kL=2 поставлено для ТКАНОГО текстилю за
# контрольованого перегляду. Він хибний для гладких поверхонь — лакова шкіра,
# глянсовий вініл, фурнітура, шовк із високим блиском, — і хибний для пари
# річ↔шкіра, бо шкіра не текстиль. Тому це НЕ дефолт `de00`, а окрема функція з
# явною умовою: змінити дефолт означало б тихо застосувати kL=2 і до обличчя.
_ГЛАДКІ = ("leather", "patent", "vinyl", "smooth-shine", "satin", "silk-shine",
           "лак", "вініл", "метал", "фурнітура")

def тканинна_пара(текстура_a=None, текстура_b=None):
    """Чи законно міряти цю пару текстильним kL=2 (R-COL-11).
    Повертає (kL, чому). Невідома текстура -> kL=1: підвищувати толерантність
    на невідомому вході означало б зливати кольори, яких ніхто не міряв."""
    for t in (текстура_a, текстура_b):
        if t is None:
            return 1, ("kL=1: текстура принаймні однієї речі не відома. R-COL-11 діє "
                       "на ТКАНОМУ текстилі; на невідомому вході толерантність не "
                       "підвищується")
        if any(str(t).strip().lower().startswith(g) or g in str(t).strip().lower()
               for g in _ГЛАДКІ):
            return 1, ("kL=1: «%s» — гладка поверхня. kL=2 поставлено для тканого "
                       "текстилю за контрольованого перегляду й хибний для лаку, "
                       "вінілу, фурнітури й шовку з високим блиском" % t)
    return 2, ("kL=2 (CIEDE2000 2:1:1, R-COL-11 · T2): обидві поверхні — тканина, "
               "різниця світлоти на текстурі перцептивно знецінюється")

# R-COL-15 — дубль `colorspace.de00_тканина`: дві метрики на дві роботи (пошук проти вердикту).
def de00_тканина(lab1, lab2, текстура_a=None, текстура_b=None):
    """ΔE00 для пари РІЧ↔РІЧ. Ніколи не для річ↔шкіра — шкіра не текстиль."""
    kL, чому = тканинна_пара(текстура_a, текстура_b)
    return de00(lab1, lab2, kL=kL), kL, чому

def _розсіяння(vals, ваги=None):
    """НЕПЕРЕРВНЕ зважене розсіяння (СКВ) — замість max−min. Використовує ВСІ точки й ваги
    (площа/надійність), не дві крайні. Повертає (σ, μ)."""
    if not vals: return (None, None)
    ваги = ваги or [1.0]*len(vals)
    S = sum(ваги) or 1.0
    μ = sum(w*x for x, w in zip(vals, ваги)) / S
    σ = (sum(w*(x-μ)**2 for x, w in zip(vals, ваги)) / S) ** 0.5
    return (σ, μ)

def _кут_розсіяння(hs_deg, ваги=None):
    """КРУГОВЕ зважене розсіяння тону (замість max-парного гепу). R=довжина результуючого
    вектора (1=зібрані, 0=розкидані); кутова СКВ = sqrt(-2·ln R). Неперервне, по всіх рисах."""
    if not hs_deg: return None
    ваги = ваги or [1.0]*len(hs_deg)
    S = sum(ваги) or 1.0
    Cc = sum(w*math.cos(math.radians(h)) for h, w in zip(hs_deg, ваги)) / S
    Ss = sum(w*math.sin(math.radians(h)) for h, w in zip(hs_deg, ваги)) / S
    R = (Cc*Cc + Ss*Ss) ** 0.5
    return round(math.degrees((-2*math.log(max(R, 1e-9))) ** 0.5), 1)
# СТЕЛЯ ХРОМИ КЕШУЄТЬСЯ ЗА ВУЗЛОМ (17.09.2026, швидкість). `c_max` — 40 ітерацій
# двійкового пошуку по гамуту, тобто 40 переводів Lab→RGB на КОЖЕН виклик, і
# чиста функція своїх трьох аргументів. Виміряно на каталог_brief.xml під наміром
# statement: 44 415 викликів, 1.78 млн `to_rgb`, 12.4 с із 37.4 профільної шкали —
# при тому, що вузли (L, h) повторюються: їх питають `c_max_поверхня` і
# `колір_образу.гучність` над тими самими речами в 200 комбінаціях.
# КЛЮЧ ТОЧНИЙ, БЕЗ ОКРУГЛЕННЯ: округлити означало б змінити відповідь, а тут
# міряється швидкість, не стеля. Межа словника — щоб довгий процес не ріс без краю.
_КЕШ_C_MAX = {}


# R-MUN-04 — дубль `colorspace.c_max`: стеля хроми — функція і hue, і value (тіло асиметричне).
def c_max(L, h, space="sRGB"):
    ключ = (L, h, space)
    v = _КЕШ_C_MAX.get(ключ)
    if v is not None:
        return v
    ar,br=math.cos(math.radians(h)),math.sin(math.radians(h)); lo,hi=0.,250.
    for _ in range(40):
        m=(lo+hi)/2
        if all(-1e-9<=c<=1+1e-9 for c in to_rgb(L,m*ar,m*br,space)): lo=m
        else: hi=m
    if len(_КЕШ_C_MAX) < 200000:
        _КЕШ_C_MAX[ключ] = lo
    return lo

# ── R-COL-12: стеля хроми РЕАЛЬНОЇ ПОВЕРХНІ, не дисплея ────────────────────
# Тема-2, R-COL-12 · T1 · default. Pointer M.R. (1980), The Gamut of Real Surface
# Colours, Color Res Appl 5(3):145–155 — максимальна хрома по сітці L*×h° з 4089
# нефлуоресцентних зразків (576 вузлів: L* 15–90 крок 5, h° 0–350 крок 10).
#
# ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after): `palette._гамут_ок` звіряв вікно палітри зі
# стелею sRGB, тобто питав «чи існує такий колір НА ЕКРАНІ». Питання мало бути «чи
# може ним бути ФАРБОВАНА ТКАНИНА». Середні збігаються (Pointer 49.7, sRGB 50.9,
# медіанне відношення 1.02) — і саме тому дефект не було видно; локальні значення
# розходяться до +68.9 і −45.0 C*. Виміряно на гейті: при C*≥24 по 540 вузлах sRGB
# пропускає 89.4%, реальні поверхні 84.6% → 46 вузлів (8.5%) — ФАНТОМНІ ВІКНА,
# пропущені гейтом і незаповнювані тканиною.
