    for m in d["моди"]: print(f"   мода L*={m['lab'][0]:5.1f} вага={m['вага']:.2f} розкид={m['розкид']}")

    print("3) ВОЛОССЯ З ПООДИНОКОЮ СИВИНОЮ (8%)")
