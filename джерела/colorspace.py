def _вузли_pointer_d65():
    """Сітка 5 L* × 10° під D65: у кожній клітинці — C* найближчого АДАПТОВАНОГО вузла."""
    адапт = {}
    for L, ряд in _POINTER_ВУЗЛИ_C.items():
        for i, C in enumerate(ряд):
            h = i * 10
            L2, C2, h2 = lch(адаптувати_освітлювач(
                (L, C*math.cos(math.radians(h)), C*math.sin(math.radians(h)))))
            адапт[(L, h)] = (L2, C2, h2 if C2 > 1e-9 else float(h))
    out = {}
    for L in _POINTER_ВУЗЛИ_C:
        for h in range(0, 360, 10):
            кандидати = [адапт[(L + dL, (h + dh) % 360)] for dL in (-5, 0, 5) for dh in (-10, 0, 10)
                         if (L + dL) in _POINTER_ВУЗЛИ_C]
            L2, C2, h2 = min(кандидати, key=lambda v: ((v[0] - L) / 5.0) ** 2
                                                       + ((((v[2] - h) + 180) % 360 - 180) / 10.0) ** 2)
            out[(L, h)] = round(C2, 2)
    return out
