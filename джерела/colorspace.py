def relation_coverage(F, step_h=2, step_L=8, rels=(0.15,0.35,0.55,0.75), min_votes=2):
    """ДАНІ, не вердикт: яку частку gamut охоплює кожне відношення для цієї особи.
    Без ok/PASS/FAIL — рішення ухвалює шар вище. Крок дрібний: дуги бувають вужчі
    за грубу сітку (моя попередня сітка 20° давала хибний нуль на дузі 24°)."""
    grid=[(L, c_max(L,h)*r*math.cos(math.radians(h)), c_max(L,h)*r*math.sin(math.radians(h)))
          for L in range(15,95,step_L) for h in range(0,360,step_h) for r in rels]
    out={}
    for rel in RELATIONS:
        n=sum(1 for lab in grid
              if sum(1 for v in feature_votes(F,lab,rel).values() if v["тон"]=="так")>=min_votes)
        out[rel]=round(n/len(grid),3)
    return out

# ── НАДІЙНІСТЬ ОСЕЙ ЗА УМОВАМИ ЗЙОМКИ (K-PC-05) ──────────────────────────────
# Освітлення діє на все обличчя однаково -> ВІДНОШЕННЯ всередині кадру виживають,
# АБСОЛЮТНІ величини — ні. Тому висновки гейтуються джерелом даних, а не видаються
# однаково для спектрофотометра й селфі на кухні.
# R-COL-06, R-COL-09 і K-COND-03 — дубль K-PC-05: надійність осі за умовами зйомки —
# колір каталожного фото не абсолют, освітлювач некерований, світло сцени судить кадр.
AXIS_RELIABILITY = {
 "spectro":      dict(value=1.0, contrast=1.0, chroma=1.0, hue=1.0, undertone=1.0),
 "protocolized": dict(value=0.9, contrast=0.9, chroma=0.7, hue=0.7, undertone=0.5),
 "uncontrolled": dict(value=0.8, contrast=0.85, chroma=0.35, hue=0.35, undertone=0.15),
}
MIN_TO_EMIT = 0.5     # T3: нижче цього вісь не несе висновків, лише повідомляється

def reliability(source="uncontrolled"):
    return AXIS_RELIABILITY[source]

# ── R-PC-10: ДВА РОДИ ПОХИБКИ ФОТО — КОНТРАСТ ВИЖИВАЄ ЛИШЕ ОДИН ──────────────
# Тема-2, R-PC-10 · T3 (симуляція над T2-вимірами Russell) · default. Контраст —
# РІЗНИЦЯ двох зон одного кадру, тож дві похибки камери діють на нього по-різному
# (REGISTRY["contrast_noise"]): спільний зсув експозиції / балансу білого ±10 % (обидві
# зони разом) → 0 % індукованої похибки — скорочується у відношенні; незалежний
# регіональний шум 2 L* на зону → 63 % міжособової SD, 4 L* → 127 %.
# Наслідок 1: абсолютна колірна калібровка для ЦІЄЇ осі не потрібна (часткове
# послаблення R-COL-09 лише для контрасту). Наслідок 2: направлене світло по обличчю
# (вікно збоку, тінь від волосся) — саме той регіональний шум, що не скорочується.
# ЩО БУЛО: `AXIS_RELIABILITY["uncontrolled"]["contrast"] = 0.85` — одна стеля за «фото
# ненадійне» без розрізнення родів шуму; регіональний шум, який `extract.zone_stats.se_L`
# уже міряє (похибка ЦЕНТРАЛЬНОЇ оцінки зони, не MAD пікселів), у гейт не входив —
# лише в `реєстр_правил._сила` окремих рішень.
# ЩО ТЕПЕР: гейт бере регіональний шум із `se_L`; спільний зсув у надійність не входить
# (0 %); стеля 0.85 ЛИШАЄТЬСЯ і не піднімається «бо симуляція» — вона тепер тримає те,
# чого симуляція не моделює (JPEG-блоки, згладжування шкіри, що б'є саме по межі
# риса/шкіра; корпус називає свої числа оптимістичною підлогою). Без `se_L` (hex-ввід,
# синтетика) надійність = стеля, як була: сила на hex-вводі НЕ зростає.
# ДЕ ЛАМАЄТЬСЯ: масштаб «4 L* → 127 %» виміряний на контрасті РИСА↔ШКІРА (Russell), а
# `outfit.контраст_особи` міряє ВОЛОССЯ↔ШКІРУ (розрив названий у R-PC-03); міжособовий
# розкид волосся↔шкіри більший, тож гасіння тут консервативне — помилка у бік
# «утримати», не у бік «стверджувати». Лінійність по se_L — з того, що ∂CF/∂L* стала.
_КОНТРАСТ_ШУМ_L, _КОНТРАСТ_ШУМ_ЧАСТКА = REGISTRY["contrast_noise"]["val"]

def похибка_контрасту(*se):
    """Похибка РІЗНИЦІ світлот двох зон із незалежними регіональними похибками —
    квадратурна сума (дисперсія різниці незалежних величин = сума дисперсій).
    Спільний зсув експозиції/ББ сюди не входить: він скорочується (R-PC-10: 0 %).
    None, якщо жодна зона похибки не несе (hex-ввід, синтетика) — як і було."""
    se = [float(s) for s in se if s]
    return round(math.sqrt(sum(s * s for s in se)), 2) if se else None

def надійність_контрасту(source="uncontrolled", se_L=None):
    """Надійність осі контрасту: стеля джерела, згашена РЕГІОНАЛЬНИМ шумом `se_L`;
    ніколи не вище стелі. `se_L` — похибка центральної оцінки L* зони
    (`extract.zone_stats.se_L`), не розкид пікселів."""
    стеля = float(AXIS_RELIABILITY[source]["contrast"])
    if not se_L:
        return dict(надійність=стеля, стеля=стеля, регіональний_шум=None, спільний_зсув=0.0,
                    чому="регіональний шум не виміряний (hex-ввід/синтетика): стеля джерела як є, "
                         "не піднімається; спільний зсув експозиції/ББ контрасту не рушить "
                         "(R-PC-10: 0 %)")
    частка = _КОНТРАСТ_ШУМ_ЧАСТКА * float(se_L) / _КОНТРАСТ_ШУМ_L
    над = round(min(стеля, max(0.0, 1.0 - частка)), 3)
    return dict(надійність=над, стеля=стеля, регіональний_шум=round(float(se_L), 2), спільний_зсув=0.0,
                чому=(f"регіональний шум se_L={float(se_L):.2f} L* на зону з'їдає {100*частка:.0f} % "
                      f"міжособового розкиду контрасту (R-PC-10: 4 L* → 127 %); спільний зсув "
                      f"експозиції/ББ — 0 %; надійність {над} під стелею {стеля}"))

def gate_conclusions(source="uncontrolled", se_L=None):
    """Що взагалі можна стверджувати за цього джерела даних.
    `F` прибрано: гейт залежить від умов зйомки, і його присутність у сигнатурі
    натякала, що профіль якось впливає — не впливає. `se_L` (R-PC-10) — виміряний
    регіональний шум профілю з фото; без нього вісь контрасту стоїть на стелі джерела."""
    R=dict(reliability(source))
    К=надійність_контрасту(source, se_L)
    R["contrast"]=К["надійність"]
    ok=[k for k,v in R.items() if v>=MIN_TO_EMIT]
    withheld=[k for k,v in R.items() if v<MIN_TO_EMIT]
    notes=[]
    if "undertone" in withheld:
        notes.append("підтон не стверджується: баланс білого некерований (R-PC-04 hard); "
                     "працювати у value-термінах, метали/білі — питати в людини")
    if "chroma" in withheld:
        notes.append("абсолютна хрома ненадійна: використовувати відносні порівняння в кадрі")
    notes.append("контраст (R-PC-10): " + К["чому"])
    if "contrast" in withheld:
        notes.append("контраст особи не стверджується: регіональний шум по обличчю перевищує те, "
                     "що вісь розрізняє; лікується рівним світлом по обличчю (без вікна збоку й "
                     "тіні від волосся), не калібруванням кольору — калібрування цій осі не допомагає")
    return dict(джерело=source, надійність=R, можна_стверджувати=ok,
                утримано=withheld, примітки=notes)

def extraction_sanity(F, min_de=8.0):
    """Самоперевірка ЕКСТРАКЦІЇ, не стилю. Якщо дві різні риси вийшли майже
    однаковими — сегментація майже напевно зачепила той самий матеріал
    (типово: «волосся» насправді шкіра). Ловить провал, якого density() не бачить,
    бо забруднений розподіл лишається одномодальним."""
    keys=[k for k in F if not k.startswith("_")]
    probs=[]
    for i in range(len(keys)):
        for j in range(i+1,len(keys)):
            a,b=F[keys[i]],F[keys[j]]
            if a["h"] is None or b["h"] is None: continue
            d=de00((a["L"],a["a"],a["b"]),(b["L"],b["a"],b["b"]))
            if d<min_de:
                probs.append(dict(риси=(keys[i],keys[j]), dE00=round(d,1),
                    діагноз="різні матеріали не можуть бути настільки схожими — "
                            "перевірити маски сегментації"))
    return dict(ok=not probs, підозри=probs)

