"""аксесуари_розмір.py — родові ворота розміру: «аксесуар → вимір тіла», ворота однієї речі, ширина й розмір взуття, регістр оправи (K-SIZ-01, K-SHO-13/14/15, K-EYE-01/02, K-HAT-01, K-WCH-01, K-GLV-01).

Виділено з `accessory.py` (19.09.2026, хвиля стандарту, СТАНДАРТ_КОДУ п.16) ЧИСТИМ
перенесенням: кожна функція й константа — байт у байт, разом із коментарями над
нею. `accessory.py` лишається фасадом і реекспортує кожне ім'я звідси; цей модуль
`accessory` не імпортує.
"""
import math
import re

import trace as _СЛ
from аксесуари_реєстр import C, _зн

# ═════════════════ 2. РОДОВІ ВОРОТА РОЗМІРУ (K-SIZ-01) ═════════════════
# Тема-10 ЧАСТИНА XXIX: три ворота, які я писав як взуттєві, не взуттєві. Кожен
# аксесуар кріпиться до виміру тіла, і невідповідність — ворота, не смак.
#
# Три виміри НЕ ДОСЛІДЖЕНО, і це позначено прямо (нуль пошуку, не нуль світу):
# обхват долоні для рукавичок, розмір пальця для каблучки, обхват шиї для чокера.
АКСЕСУАР_ВИМІР = {
 "взуття":        dict(вимір="довжина_стопи_мм", поле="устілка_см", стандарт="ISO 9407:2019",
                       правило="K-SHO-13"),
 "окуляри":       dict(вимір="міжзіницева_мм", поле="оправа", стандарт="BS 3521:2:1991",
                       правило="K-EYE-01"),
 "головний_убір": dict(вимір="голова_см", поле="обхват_голови_см", стандарт="модистська болванка",
                       правило="K-HAT-01"),
 "годинник":      dict(вимір="зап'ястя_см", поле="lug_мм", стандарт=None, правило="K-WCH-01"),
 "рукавички":     dict(вимір="долоня_см", поле="bl", стандарт=None, правило="K-GLV-01",
                       не_досліджено="обхват долоні — розмірної системи не брав"),
}
# ПРИКРАС ТУТ НЕМА НАВМИСНО. Прогін показав, що з ними таблиця воріт емітувала
# «питання» на КОЖНОМУ образі з кольє — бо вимір тіла для прикрас не існує в принципі
# (тема сама ставить у своїй таблиці прочерк і «стандарту нема»). Правило кольє —
# K-JEW-01 — не про розмір тіла, а про відстань між двома краями, і живе воно у
# `кольє_проти_горловини`. Тримати його ще й тут означало б рахувати одне правило двічі
# і засмічувати ворота питанням, на яке відповіді не буде.
# Три виміри тема НЕ ДОСЛІДЖУВАЛА, і це нуль пошуку, а не нуль світу — записано в
# БЕЗ_ВХОДУ під K-SIZ-01, щоб було видно як чергу, а не як тишу.


def ворота_розміру(t, речі):
    """K-SIZ-01 + K-SHO-13/14/15 + K-EYE-01 + K-HAT-01 + K-WCH-01 + K-GLV-01.

    ЩО ЦЕ МІНЯЄ (before/after). before — ворота посадки існували для одягу; аксесуар
    вважався безрозмірним, а взуття не мало поняття розміру взагалі, тож пара будь-якого
    розміру була кандидатом. after — зʼявляється єдина таблиця «аксесуар → вимір тіла»,
    і вся аксесуарна гілка дістає той самий АБСОЛЮТНИЙ фільтр, що й одяг: з видачі
    зникає цілий клас пропозицій, які людина фізично не надіне.

    K-SHO-15 (обовʼязково): розмір використовується ЛИШЕ щоб ВІДКИДАТИ, ніколи щоб
    упорядковувати. Комісія зі стандарту сама каже, що посадку взуття визначають
    щонайменше тридцять вісім факторів, здебільшого субʼєктивних, з яких ми
    спостерігаємо один. Ранжувати за такою величиною було б рівно тим декоративним
    виміром, який забороняє K-IO-05.

    Повертає (лишились, знахідки). Річ без входу НЕ відкидається — вона лишається з
    «питанням», бо мовчазне відкидання за невідомим полем гірше за прохід.
    """
    виміри = (t or {}).get("аксесуарні") or {}
    лишились, зн = [], []
    for р in речі:
        сл = р.get("слот")
        назва = р.get("назва") or р.get("id") or "річ"
        сп = АКСЕСУАР_ВИМІР.get(сл)
        if not сп:
            лишились.append(р); continue
        хотів_відкинути, з = _ворота_однієї(сл, сп, р, назва, виміри)
        if з:
            зн.append(з)
        # ЗНАЙДЕНО ПРОГОНОМ, НЕ ЧИТАННЯМ. Перша версія відкидала річ за власним
        # локальним прапорцем — а знахідка при цьому виходила з регістром «репліка»
        # (бо стеля тіру звалила силу). Тобто річ зникала з видачі, а текст поруч
        # казав, що нічого не блокує. Абсолютний фільтр, який діє ПОЗА власним
        # регістром, не є абсолютним — він є звичкою, і це той самий дефект, який
        # наскрізний прогін уже ловив на жорсткому «ні».
        # Тепер джерело правди одне: `блокує` самої знахідки.
        відкинути = bool(хотів_відкинути and з and з.get("блокує"))
        if хотів_відкинути and not відкинути and з is not None:
            з["чому"] = з["чому"] + ("; річ НЕ відкинуто: стеля тіру звела це правило до "
                                     "репліки, а репліка не має права діяти як фільтр")
        if not відкинути:
            лишились.append(р)
    # ── «ПЕРЕВІРЕНО Й ЧИСТО» ЛИШАЄ СЛІД ТАК САМО, ЯК «СПРАЦЮВАЛО» ────────────
    # ЗНАЙДЕНО НАСКРІЗНИМ ПРОГОНОМ 26.08.2026: пара, що ПРОЙШЛА ворота розміру,
    # лишала в лозі рівно те саме, що пара, для якої ворота не викликались, —
    # порожнечу. Тобто за слідом не можна було відрізнити «правило перевірило й
    # пропустило» від «правило не працювало», і гейт досяжності рахував K-SHO-13/14/15
    # мертвими на кожному образі, де взуття підходить.
    # Це рівно той висновок, який `language_gate` уже зробив для анти-правил
    # («промовчало правильно» і «ніколи не викликалось» — різні речі), і він
    # виявився загальним, а не властивістю мовного шару.
    for р in речі:
        сп_ = АКСЕСУАР_ВИМІР.get(р.get("слот"))
        if not сп_:
            continue
        спрацювало = any(з.get("речі") and (р.get("назва") or р.get("id")) in з["речі"]
                         for з in зн)
        if not спрацювало:
            _СЛ.запис(сп_["правило"], "ворота розміру", "ворота_розміру",
                      значення="перевірено, у смузі", сила=0.0,
                      напрям="пройдено — це ВИКОНАНЕ правило, не мовчання")
    if зн:
        _СЛ.запис("K-SIZ-01", "аксесуар кріпиться до виміру тіла", "ворота_розміру",
                  значення="перевірено %d, відкинуто %d" % (len(речі), len(речі) - len(лишились)),
                  сила=None, напрям="ворота перед естетикою")
    return лишились, зн


def _ворота_однієї(сл, сп, р, назва, виміри):
    """Ворота розміру однієї речі за рядком АКСЕСУАР_ВИМІР `сп`: (чи є знахідка, знахідка).

    Без обох чисел (вимір людини і поле речі) ворота не рахуються й виходять
    «питанням» із названим браком — мовчазний прохід заборонено (K-IO-04)."""
    прав = сп["правило"]
    вимір_людини = виміри.get(сп["вимір"]) if сп["вимір"] else None
    поле = р.get(сп["поле"])
    # ── нема входу: правило мовчить ГУЧНО ────────────────────────────────────
    if вимір_людини is None or поле is None:
        бракує = []
        if сп["вимір"] and вимір_людини is None: бракує.append("вимір людини «%s»" % сп["вимір"])
        if поле is None: бракує.append("поле речі «%s»" % сп["поле"])
        з = dict(_зн(прав, "питання",
            "ворота розміру не перевірено: %s" % ", ".join(бракує), [назва],
            "невідповідність розміру — ворота, не смак; але без обох чисел ворота не "
            "рахуються, і система не має права вдавати, що річ пройшла перевірку"
            + ("; %s" % сп["не_досліджено"] if сп.get("не_досліджено") else ""),
            ремонт=("одне питання анкети: %s" % сп["вимір"]) if вимір_людини is None
                   else "картка не несе поля «%s»" % сп["поле"],
            ламається="анкета коштує хвилину на вимір; поля картки не коштують нічого, "
                      "але український роздріб дає їх нерегулярно"),
            сила_нп=0.0, сила_нп_джерело="входу нема: %s" % "; ".join(бракує))
        з["навіщо"] = "розблокує %s (%s)" % (прав, сп.get("стандарт") or "без стандарту")
        return False, з
    # ── взуття: устілка проти стопи (K-SHO-13) ───────────────────────────────
    if сл == "взуття":
        припуск = float(поле) * 10.0 - float(вимір_людини)
        if C["припуск_мін_мм"] <= припуск <= C["припуск_макс_мм"]:
            return False, None
        # ДВІ СТОРОНИ СМУГИ МАЮТЬ РІЗНУ ДОКАЗОВУ БАЗУ, І КОД ЦЕ ПОКАЗУЄ.
        #   замало  → джерельна межа (ISO 9407 означує довжину стопи; фітингова
        #             література: внутрішня довжина щонайменше на 5 мм більша).
        #             K-SHO-13, strong → гейт → річ ВІДКИДАЄТЬСЯ.
        #   забагато → межі в джерелах НЕМА («ширина великого пальця» — одиниця без
        #             числа). K-SHO-15, soft → репліка → річ ЛИШАЄТЬСЯ, вартість названа.
        # Перша версія відкидала з обох боків однаково — тобто фольклорна константа
        # діяла як абсолютний фільтр нарівні зі стандартом. Це рівно те, що забороняє
        # інваріант «сила ≤ верифікація», і виявилось воно прогоном, не читанням.
        if припуск < C["припуск_мін_мм"]:
            return True, dict(_зн("K-SHO-13", "strong",
                "припуск %+.0f мм — замало" % припуск, [назва],
                "внутрішня довжина %s см = %.0f мм проти стопи %.0f мм; джерельний мінімум "
                "%.0f мм; пальці бʼються при кроці: пухирі між пальцями, мозолі, потовщені нігті"
                % (поле, float(поле) * 10, float(вимір_людини), C["припуск_мін_мм"]),
                ремонт="інший розмір цієї моделі, або інша модель у смузі припуску",
                ламається="той самий номер Mondopoint НЕ гарантує тієї самої посадки — стандарт "
                          "каже це сам: колодка робиться під тип і стиль взуття, під модуль і "
                          "розтяг матеріалів верху, під товщину панчішних виробів. Розтяжний "
                          "верх терпить тісніший припуск, жорсткий — ні. І стопа змінюється з "
                          "віком, вагою, вагітністю: збережена довжина має термін придатності, "
                          "переміряти раз на 1–2 роки",
                поріг=C["припуск_мін_мм"], вимір=припуск),
                сила_нп=round(min(1.0, (C["припуск_мін_мм"] - припуск) / 10.0 + 0.5), 2),
                сила_нп_джерело="вимір (устілка − стопа, мм; межа джерельна)")
        return False, dict(_зн("K-SHO-15", "soft",
            "припуск %+.0f мм — забагато" % припуск, [назва],
            "стопа ковзатиме всередині: пухирі від ковзання. АЛЕ верхньої межі припуску "
            "джерела не дають — «ширина великого пальця» це антропометрична одиниця без "
            "числа, тому %.0f мм тут МОЯ оцінка, і річ не відкидається"
            % C["припуск_макс_мм"],
            ремонт="приміряти; півромзіру менше, якщо пʼята не тримається",
            ламається="розмір — ворота, НІКОЛИ не скор: комісія зі стандарту сама каже, що "
                      "посадку взуття визначають щонайменше тридцять вісім факторів, "
                      "здебільшого субʼєктивних, з яких ми спостерігаємо один. Тому смуга "
                      "поставлена ШИРОКО й відкидає лише ясні провали; межовий кандидат, "
                      "відкинутий помилково, — реальна втрата на такому тонкому каталозі",
            поріг=C["припуск_макс_мм"], вимір=припуск),
            сила_нп=round(min(0.7, (припуск - C["припуск_макс_мм"]) / 20.0 + 0.25), 2),
            сила_нп_джерело="вимір (устілка − стопа, мм; межа фольклорна)")
    # ── окуляри: міжзіницева ≤ PD оправи (K-EYE-01) ──────────────────────────
    if сл == "окуляри":
        pd = _pd_оправи(поле)
        if pd is None:
            return False, dict(_зн("K-EYE-01", "питання",
                "трійка оправи не читається з «%s»" % поле, [назва],
                "оправа несе власні розміри універсально: розмір ока, DBL (міст) і заушник, "
                "друковані на самій оправі, звично трійкою штибу 52-18-140; PD оправи = "
                "розмір ока + DBL",
                ремонт="узяти трійку зі специфікації товару",
                ламається="сонцезахисні й коригувальні мають різну строгість: для сонцезахисних "
                          "центрування зіниці не критичне, важать лише загальний розмір і міст"),
                сила_нп=0.0, сила_нп_джерело="входу нема (трійка оправи не розібрана)")
        if float(вимір_людини) <= pd:
            return False, None
        return True, dict(_зн("K-EYE-01", "strong",
            "міжзіницева %.0f мм більша за PD оправи %.0f мм" % (float(вимір_людини), pd), [назва],
            "BS 3521:2:1991 і фахова література з офтальмічного диспенсингу: міжзіницева "
            "відстань мусить бути МЕНШОЮ АБО РІВНОЮ PD оправи. Це вимірна посадка, і вона "
            "старша за естетику",
            ремонт="оправа з більшим розміром ока або ширшим містком",
            ламається="для сонцезахисних центрування зіниці не критичне — правило не можна "
                      "застосовувати однаково до обох класів",
            поріг=pd, вимір=float(вимір_людини)),
            сила_нп=round(min(1.0, (float(вимір_людини) - pd) / 6.0 + 0.3), 2),
            сила_нп_джерело="вимір (міжзіницева − PD оправи, мм)")
    # ── капелюх: обхват голови (K-HAT-01) ────────────────────────────────────
    if сл == "головний_убір":
        розб = abs(float(поле) - float(вимір_людини))
        if розб <= 1.5:
            return False, None
        return True, dict(_зн("K-HAT-01", "strong",
            "обхват %s см проти голови %.1f см" % (поле, float(вимір_людини)), [назва],
            "обхват міряють по найбільшій частині черепа, приблизно на дюйм вище брів, через "
            "потиличну кістку, стрічкою паралельно землі; допускається запас на два пальці. "
            "Невідповідність — не «менш вигідно», це річ, яку не надіти",
            ремонт="інший розмір болванки",
            ламається="український роздріб масово продає головні убори як «один розмір» — "
                      "на таких речах ворота не спрацюють, і це має бути видно як «нема входу»",
            поріг=1.5, вимір=розб),
            сила_нп=round(min(1.0, розб / 4.0), 2), сила_нп_джерело="вимір (|обхват − голова|, см)")
    # ── годинник: lug-to-lug проти зап'ястка (K-WCH-01) ──────────────────────
    if сл == "годинник":
        діаметр = float(вимір_людини) * 10.0 / math.pi
        стеля = діаметр * C["lug_частка"]
        if float(поле) <= стеля:
            return False, None
        return False, dict(_зн("K-WCH-01", "soft",
            "lug-to-lug %.0f мм при пласкій частині зап'ястка ≈ %.0f мм" % (float(поле), стеля),
            [назва],
            "вирішує lug-to-lug, а НЕ діаметр корпусу: корпус 39 мм із lug-to-lug 47,5 мм сідає "
            "спокійно там, де корпус 44 мм із lug-to-lug 53 мм давить те саме зап'ястя",
            ремонт="корпус із коротшими вушками, не обовʼязково менший діаметром",
            ламається="коефіцієнт 75–80 % — комерційний, некалібрований; сусіднє число тієї ж "
                      "лінії джерело САМО позначило як rule of thumb. Український роздріб "
                      "lug-to-lug здебільшого не публікує, лише діаметр — а джерела прямо "
                      "кажуть, що діаметр вирішує менше",
            поріг=стеля, вимір=float(поле)),
            сила_нп=round(min(1.0, (float(поле) - стеля) / 8.0 + 0.3), 2),
            сила_нп_джерело="вимір (lug-to-lug − стеля зап'ястка, мм)")
