def формат_хустки(речі):
    """[знахідки] K-CRA-12: формат гейтить те, ЯКІ рішення про вузол узагалі існують.

    ЧОМУ СЛІДУ НЕ БУЛО, І ЦЕ НЕ ПРО ПРАВИЛО. Ворота формату написані двічі —
    `feed.слоти` відсікає ними місця («формат %d см відсікає повне обгортання,
    плечі й „як верх"»), `команди_розкладки` нижче друкує рядок `ворота_формату`.
    Обидві читають `розмір_см`, а В ЗАПИС КАТАЛОГУ це число не клалось: `слоти()`
    рахувала його й віддавала нікому. На живому шляху `р.get("розмір_см")` було
    None у 100 % випадків, тобто ворота відповідали «розмір невідомий» ЗАВЖДИ і не
    відсікли жодного місця жодного разу. Число тепер їде записом каталогу.

    І ДРУГА ПОЛОВИНА: `команди_розкладки` віддає ОПЦІЇ З КОМПРОМІСАМИ, а не
    знахідки, — і це рішення домену (канонічний авторитет відмовляється робити
    вибір вузла правилом). Але ФІЗИЧНІ ворота вибором не є: 70 см на повне
    обгортання голови не вистачає незалежно від чийогось смаку. Тому саме вони —
    і тільки вони — виходять знахідкою.

    ВИМІР (`каталог_повний`, 17.09.2026): 93 хустки/шарфи; квадратний формат у
    назві несуть 6 — 49, 49, 70, 84, 84, 120 см. П'ять із шести нижчі за поріг
    обгортання (90 см, T3, `РЕЄСТР["хустка_обгортання_см"]`). Решта 87 формату не
    називають: для них правило каже «входу нема» силою «питання», а не мовчить."""
    зн = []
    поріг = C["хустка_обгортання_см"]
    for р in речі:
        if р.get("слот") != "шарф":
            continue
        назва = р.get("назва") or р.get("id") or "хустка"
        розмір = р.get("розмір_см")
        if розмір is None:
            зн.append(dict(_зн(
                "K-CRA-12", "питання",
                "формат хустки не названий — які вузли можливі, невідомо", [р],
                "ворота формату ФІЗИЧНІ: сторона квадрата вирішує, чи вистачить "
                "матеріалу на повне обгортання голови, на плечі й на «як верх». "
                "Картка сторони не називає, тож жодне з семи місць ні відсікти, ні "
                "підтвердити не можна",
                ремонт=["поле розміру квадрата в картці («90х90») — інакше вхід "
                        "береться лише з опису"],
                ламається="в українському роздробі формат пишуть регулярно, але не "
                          "всі: 6 із 93 хусток каталогу"),
                сила_нп=0.0,
                сила_нп_джерело="входу нема: сторони квадрата картка не називає",
                заяви=[_ВМ.заява("scarf_size_unknown", item=_ВМ.вільний(назва, межа=44))]))
            continue
        відсічені = [м for гр, м in ФОРМАТИ_ХУСТКИ if розмір >= гр]
        місця = відсічені[0] if відсічені else ФОРМАТИ_ХУСТКИ[-1][1]
        якщо_повне = розмір >= поріг
        if якщо_повне:
            continue                    # ворота відкриті: усі рішення доступні
        зн.append(dict(_зн(
            "K-CRA-12", "default",
            "формат %d см: повне обгортання голови неможливе" % розмір, [р],
            "поріг обгортання — %d см; доступні місця для цього формату: %s. Це "
            "ворота ФІЗИЧНІ, не смакові: матеріалу просто не вистачає"
            % (поріг, ", ".join(місця)),
            ремонт=["обрати місце з доступних: %s" % ", ".join(місця[:3]),
                    "АБО квадрат від %d см, якщо потрібне саме обгортання" % поріг],
            заяви=[_ВМ.заява("scarf_too_small_for_head_wrap", side_cm=розмір, wrap_from_cm=поріг)],
            ремонт_заяви=[_ВМ.заява("choose_available_scarf_place",
                                    places=[_ВМ.код_або_невідомо("wear_place", м) for м in місця[:3]],
                                    wrap_from_cm=поріг)],
            ламається="саме число 90 — з роздрібного опису форматів Hermès, не з "
                      "виміру (T3). Ворота фізичні, поріг — конвенція",
            поріг=float(поріг), вимір=float(розмір), повна=float(поріг))))
    return зн


