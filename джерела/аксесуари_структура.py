def носій_приобличчевого_поля(речі, стан_шару=None):
    """Хто в ЦЬОМУ образі займає приобличчеве поле. None — ніхто.

    ⚠ ПЕРЕПИСАНО 26.08.2026, КОЛИ УМОВА ВПЕРШЕ СТАЛА ПЕРЕВІРНОЮ.
    Тема-10 записала умову дослівно: «шарф під застібнутим пальтом приобличчевого поля
    не займає». Але на момент запису верхнього шару зі СТАНОМ у системі не існувало, і
    умова лягла на поле `поверх_шару`, якого В ЖИВОМУ ШЛЯХУ НЕ ПИСАВ НІХТО. Тобто вона
    читалась як виконана й не виконувалась: шарф під застібнутим пальтом далі звільняв
    приобличчеве вікно верху.
    Тема-11 дала кожному верхньому шару `стан` («застібнуто / розстібнуто / накинуто»),
    і тепер умова ОБЧИСЛЮЄТЬСЯ з нього, а не з поля-привида.

    ЧОМУ ЦЕ НЕ ДРІБНИЦЯ: K-ACC-07 — правило, яке РОЗШИРЮЄ каталог (на ager 62 → 98
    досяжних верхів). Спрацювати на шарфі, якого не видно, означає звільнити
    приобличчеве колірне вікно на підставі поверхні, якої ніхто не бачить, — тобто
    впустити у видачу речі, відкинуті по суті правильно.

    ЯК ЧИТАЄТЬСЯ СТАН (і чому саме так):
      · «застібнуто» — фронт закритий, шарф ПІД ним поля не займає. Виняток один:
        шарф, явно покладений ПОВЕРХ шару (`поверх_шару=True`) — його видно.
      · «розстібнуто» / «накинуто» — лацкани відкривають V, у якому шарф якраз і живе
        (це прямо механізм K-OUT-09: «довші лацкани відкривають V, у якому є місце
        для шарфа»). Поле займається.
      · верхнього шару нема — умова беззмістовна, шарф видно завжди.

    ДЕ ЛАМАЄТЬСЯ: «видно / не видно» тут БІНАРНЕ, а насправді неперервне — під
    розстібнутим пальтом видно менше шарфа, ніж без пальта взагалі, і приобличчева
    площа має падати, а не лишатись тією самою. Площі шарфа в стані ми не рахуємо, і
    правило поводиться так, ніби вона незмінна. Це наступний кандидат на вимір.
    """
    # ⚠ МОВЧАЗНИЙ ДЕФОЛТ «ШИЯ» ПРИБРАНО 26.08.2026 — ЦЕ БУЛА ВЛАСНА СУПЕРЕЧНІСТЬ.
    # Докстрока `feed.слоти` говорить дослівно: «`місце` лишається None НАВМИСНО:
    # його ставить композитор, і поки він цього не зробив, жодне правило місця
    # застосовувати не можна. Мовчазний дефолт «шия» повернув би стару помилку під
    # новим імʼям». А цей рядок робив рівно `(р.get("місце") or "шия")` — тобто
    # необрана хустка займала приобличчеве поле нарівні з обраною, і K-ACC-07
    # звільняв колірне вікно верху (62 → 98 на ager) на підставі рішення, якого
    # ніхто не ухвалював.
    # Тепер необране місце = НЕВІДОМО, і носія нема. Це та сама лінія, що «без
    # входу ≠ пройдено»: правило не має права діяти на власному припущенні.
    # ── ТРЕТЯ ПІДСТАВА: ВИБІР НЕ ЗРОБЛЕНО, АЛЕ ВІН НІЧОГО НЕ МІНЯЄ ───────────
    # ⚠ ЧОМУ ЦЕ НЕ ПОВЕРНЕННЯ МОВЧАЗНОГО ДЕФОЛТУ, ЗНЯТОГО 26.08.2026. Той дефолт
    # ставив `місце or "шия"` — тобто ОБИРАВ за композитора одне з семи місць і
    # діяв так, ніби вибір зроблено. Тут інше твердження й воно перевірне: коли
    # УСІ допустимі місця речі приобличчеві, приобличчеве поле займається В
    # БУДЬ-ЯКІЙ гілці невирішеного вибору. Правило не припускає нічого — воно
    # застосовує те, що істинне на кожному варіанті.
    # Такі речі в каталозі є, і їх мало: снуд, хомут і шарф-краватка мають
    # замкнену конструкцію, тож `feed.слоти` лишає їм ("шия", "волосся") — 3 із
    # 93 шарфів (3.2 %, виміряно 17.09.2026 на `каталог_повний.xml`).
    ПРИОБЛИЧЧЯ = ("шия", "волосся", "плечі")

    def _займає(р):
        """Чи річ стоїть у приобличчевому полі: обране місце з ПРИОБЛИЧЧЯ або ВСІ її можливі місця там."""
        м = р.get("місце")
        if м in ПРИОБЛИЧЧЯ:
            return True
        місця = tuple(р.get("місця") or ())
        return bool(місця) and all(x in ПРИОБЛИЧЧЯ for x in місця)

    закрито = any(р.get("слот") == "верхній_шар" and р.get("стан") == "застібнуто"
                  for р in речі)
    for р in речі:
        if р.get("слот") == "шарф" and _займає(р):
            if закрито and р.get("поверх_шару") is not True:
                continue
            if р.get("поверх_шару") is False:
                continue
            return р
    for р in речі:
        if р.get("слот") == "окуляри":
            return р
    return None


