def _hex_список(v):
    """Замір кольору (рядок або список замірів) → список hex; порожнє — []."""
    return [str(x) for x in (v if isinstance(v, (list, tuple)) else [v]) if x not in (None, "")]


def особа(шкіра, волосся, очі, зріст=None, обхвати=None, намір=None):
    """Факти про неї для руки 3 — рівно те, що має код на вході, без висновків.

    Виміряне йде ВСЕ, списками: доти промпт брав перший замір і казав «ще N замір(и)»,
    бо repr списку був пітонівським синтаксисом (29.08.2026); у JSON список — це дані.
    Контраст, колорит, вікна палітри, тип фігури сюди НЕ йдуть: інакше в руку «без
    коду» витікала б робота коду (28.08.2026). Намір «conventional» — не намір (як доти)."""
    о = {}
    for ключ, v in (("skin_hex", шкіра), ("hair_hex", волосся), ("eyes_hex", очі)):
        сп = _hex_список(v)
        if сп:
            о[ключ] = сп if len(сп) > 1 else сп[0]
    if зріст not in (None, ""):
        о["height_cm"] = round(float(зріст))
    м = {(_ВМ.код("girth", к) or к): round(float(v)) for к, v in (обхвати or {}).items()
         if v not in (None, "")}
    if м:
        о["girths_cm"] = м
    if намір and намір != "conventional":
        о["intent"] = намір
    return о


def головний_колір(вибір):
    """Колір, навколо якого будується образ, — у всіх чотирьох руках однаково.

    Правило 3 (див. `brief.основний_колір`): доти обраний колір знали лише руки з кодом,
    і різницю вердиктів приписували коду. Хто обрав — даними: «вона», «код, і вона не
    міняла» (за замовчуванням ≠ вибір, `brief.бриф`), «колір її речі з фото» (рядок 152)."""
    б = (вибір or {}).get("база")
    if not б:
        return None
    слово = str(б).split("·")[0]
    о = {"name": _ВМ.код("color_name", слово) or слово}
    if (вибір or {}).get("база_hex"):
        о["hex"] = вибір["база_hex"]
    о["chosen_by"] = ("her_item_photo" if вибір.get("база_з_речі")
                      else "code_she_kept_it" if вибір.get("база_за_замовчуванням") else "her")
    return о


def її_речі(речі_паспорта):
    """Її закріплені речі з повним описом — кодами полів, без слота.

    «Речі, які отримує функціональна модель, — завжди з повним описом. Модель сама знає,
    що джинси — низ: місце речі в образі їй НЕ прописувати» (власник, 24–25.09). `id` —
    той самий, що на картці («її-ф1»): ним перелік позначає її річ (`own`). Колір — слово
    виміру (свідок сильніший за слово моделі) і hex виміру, коли код міряв."""
    вих = []
    for р in _РФ.закріплені(речі_паспорта):
        вим = р.get("вимір") or {}
        о = {"id": _РФ.ПРЕФІКС_ІД + str(р.get("ід") or "ф?")}
        if р.get("назва"):
            о["name"] = р["назва"]
        колір = вим.get("слово") or р.get("колір")
        if колір:
            о["color"] = _РФ.код_поля("color", колір) or колір
        if вим.get("hex"):
            о["color_hex"] = вим["hex"]
        for поле, ключ in (("cut", "крій"), ("length", "довжина"), ("fabric", "матеріал"),
                           ("pattern", "принт")):
            к = _РФ.код_поля(поле, р.get(ключ))
            if к:
                о[поле] = к
        о["photo"] = bool(р.get("фото"))
        вих.append(о)
    return вих


