def промпт_переліку(речі_паспорта=None, мова_тексту=None):
    """Промпт переліку рядком JSON; опис руки — `ЗАГЛУШКОЮ_ОПИСУ` (її міняє показ)."""
    її = [{к: v for к, v in р.items() if к in ("id", "name")} for р in її_речі(речі_паспорта)]
    о = ПЕРЕЛІК
    if not її:
        # без її речей поля «own» у скелеті нема: відповідати нема чим, а зайвий рядок — токени
        import dataclasses as _dc
        о = _dc.replace(ПЕРЕЛІК, скелет={"items": [{к: v for к, v in ПЕРЕЛІК.скелет["items"][0].items()
                                                    if к != "own"}]})
    return _json.dumps(_ЗП.зібрати(о, dict(description=ЗАГЛУШКА_ОПИСУ, her_items=її), мова_тексту=мова_тексту),
                       ensure_ascii=False)


_HEX = _re.compile(r"^#[0-9a-fA-F]{6}$")


def речі_переліку(відповідь):
    """Відповідь ПЕРЕЛІКУ → [{назва, деталі, слот, код_слота, hex, own}] або None.

    None означає рівно «переліку нема» (не JSON, без «items», порожній) — далі розбір
    прози, як доти. Слот — ключ ядра за таблицею внутрішньої мови; код поза нею лишає
    `слот` None і `код_слота` як є: річ без слота розбір називає, а не губить мовчки."""
    об, _причина = _ПР.розбір(відповідь)
    if об is None:
        try:
            об = _json.loads(re_огорожа(str(відповідь or "")))
        except ValueError:
            return None
    items = об.get("items") if isinstance(об, dict) else об
    if not isinstance(items, list):
        return None
    вих = []
    for о in items:
        if not isinstance(о, dict):
            continue
        назва = " ".join(str(о.get("name") or "").split())[:80]
        if not назва:
            continue
        код = None if _ВМ.невідомо(о.get("slot")) else str(о.get("slot")).strip()
        hx = str(о.get("color_hex") or "").strip()
        own = None if _ВМ.невідомо(о.get("own")) else str(о.get("own")).strip()
        вих.append(dict(назва=назва, деталі=" ".join(str(о.get("details") or "").split())[:160] or None,
                        слот=_ВМ.ключ("slot", код), код_слота=код,
                        hex=(hx.lower() if _HEX.match(hx) else None), own=own))
    return вих or None


def re_огорожа(т):
    """Огородження ```json на КІНЦЯХ відповіді — геть; усередину код не заглядає."""
    return _re.sub(r"^\s*```(?:json)?\s*|\s*```\s*$", "", т)
