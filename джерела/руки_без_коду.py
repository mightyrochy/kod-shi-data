# ═══════════ 3. ПЕРЕЛІК: РЕЧІ ОБРАЗУ ДАНИМИ ══════════════════════════════════════
# ЧОМУ ЦІ РЯДКИ:
#   · «description» підставляє показ відповіддю руки (`ЗАГЛУШКА_ОПИСУ` — рядок JSON, який
#     показ міняє на JSON.stringify(текст)): від випадку промпт не залежить, один виклик мосту
#     на випадок (Т-8);
#   · «own» — її річ позначає ID, а не мітка в назві: мітку перелік губив, і на картці її
#     спідниця ставала «річчю вигаданою» (розбір 2/8, В-1, В-2);
#   · «slot» — кодом із переліку в скелеті: слово слота в коді було словником, і «козаки»,
#     «ботфорти», «челсі» з картки зникали (В-3); місце речі модель знає сама, лише називає кодом;
#   · «name» / «details» — словами опису: перелік не складає образ, а переказує той, який
#     вона читає (Т-8: «жодної звірки: що модель назвала, те й іде»);
#   · порядок — як в описі: картка, переставлена по слотах, читалась би як інший образ.
# Слоти — УСЯ таблиця внутрішньої мови (25 кодів), переліком прямо в скелеті: вигадана рука
# кладе в образ і колготи, і окуляри, і рукавички, а кожен із 25 проходить `композитор_річ.у_річ`
# (виміряно). `accessory` — для речі, якій інший код не пасує: рукавички без свого
# коду модель назвала «accessory», і вони з картки зникали).
ПЕРЕЛІК = _ЗП.Оголошення(
    задача="перелік_речей",
    роль="You read the description of an outfit and list its items as data.",
    вхід=(
        _ЗП.Поле("description", "the outfit description", треба=True),
        _ЗП.Поле("her_items", "her own items", як="an item of the description that is one of them gets its "
                                                   "id in \"own\""),
    ),
    правила=(
        "One object per item — garment, shoes, bag, accessory, jewelry — in the order of the "
        "description, with its words and hex.",
        # Опис може назвати слот непотрібним («no cardigan is needed»,
        # «tights are not needed»), тому модель передає рішення кодом `worn`,
        # щоб показ не малював згаданий слот річчю.
        "A slot the description says is not needed is not an item: give it worn false. One item "
        "carries one thing — of two alternatives list the first; a note in brackets is not an item.",
        "Slot \"accessory\" is for an item no other slot fits.",
        # Рука може відповісти відмовою замість образу, а перелік — вигадати приклад і зробити відмову карткою.
        # Слів код не читає (п.12): чи опис — образ,
        # каже кодом `is_outfit` модель, що його читає; картка руки — лише на «yes».
        "\"is_outfit\" says whether the description is an outfit: no — when in place of items it has a "
        "refusal, a question or a note; then items is empty.",
    ),
    вихід="ITEM_LIST",
    скелет={"is_outfit": "yes|no",
            "items": [{"name": "<what the item is>",
                       "details": "<its cut, length and fabric>",
                       "slot": "|".join(_ВМ.ТАБЛИЦЯ["slot"]),
                       "color_hex": "<#rrggbb or null>",
                       "own": "<id from her_items or null>",
                       "worn": "<true, or false when the description says the outfit goes without it>"}]},
    # `невідомо` тут не стоїть: «or null» уже в скелеті тих двох полів, де відповіді може не бути
    межі=("лише_вхід",),
    мова_промпту="en",
)


def промпт_переліку(речі_паспорта=None, мова_тексту=None):
    """Промпт переліку рядком JSON; опис руки — `ЗАГЛУШКОЮ_ОПИСУ` (її міняє показ)."""
    її = [{к: v for к, v in р.items() if к in ("id", "name")} for р in її_речі(речі_паспорта)]
    о = ПЕРЕЛІК
    if not її:
        # без її речей поля «own» у скелеті нема: відповідати нема чим, а зайвий рядок — токени
        import dataclasses as _dc
        о = _dc.replace(ПЕРЕЛІК, скелет=dict(ПЕРЕЛІК.скелет, items=[{к: v for к, v in ПЕРЕЛІК.скелет["items"][0].items()
                                                                  if к != "own"}]))
    return _json.dumps(_ЗП.зібрати(о, dict(description=ЗАГЛУШКА_ОПИСУ, her_items=її), мова_тексту=мова_тексту),
                       ensure_ascii=False)


_HEX = _re.compile(r"^#[0-9a-fA-F]{6}$")


def _слот_за_назвою(код):
    """Ключ ядра за кодом слота від моделі — з прийомом ЇЇ ЗАПИСУ коду: регістр, пробіл чи дефіс
    замість «_» і однина/множина («bottoms» — це `bottom`, «accessories» — `accessory`). Інший код — не слот: `слот` None, код лишається як
    є і йде у звіт (`без_слота`). Сенс слів («jacket» — `outerwear`?) тут не вгадується: це вже логіка рук."""
    if _ВМ.невідомо(код):
        return None
    к = _re.sub(r"[\s\-]+", "_", str(код).strip().lower())
    for в in (к, к[:-1] if к.endswith("s") else None, к[:-2] if к.endswith("es") else None,
              к[:-3] + "y" if к.endswith("ies") else None, к + "s"):
        if в and _ВМ.ключ("slot", в) is not None:
            return _ВМ.ключ("slot", в)
    return None


def речі_переліку(відповідь):
    """Відповідь ПЕРЕЛІКУ → [{назва, деталі, слот, код_слота, hex, own}] або None.

    None означає рівно «переліку нема» (не JSON, без «items», порожній) — далі розбір
    прози, як доти. Слот — ключ ядра за таблицею внутрішньої мови; код поза нею лишає
    `слот` None і `код_слота` як є: річ без слота розбір називає, а не губить мовчки.
    `носить` False — модель позначила слот непотрібним (`worn` false): далі в образ він не йде,
    але розбір його називає (`не_потрібні`), а не губить мовчки."""
    об, _причина, _ = _ПР.розбір_останній(відповідь, ("items",))
    if об is None:
        try:
            об = _json.loads(re_огорожа(str(відповідь or "")))
        except ValueError:
            return None
    items = об.get("items") if isinstance(об, dict) else об
    if not isinstance(items, list):
        return None
    вих = []
    for о in items:
        if not isinstance(о, dict):
            continue
        назва = " ".join(str(о.get("name") or "").split())[:80]
        if not назва:
            continue
        код = None if _ВМ.невідомо(о.get("slot")) else str(о.get("slot")).strip()
        hx = str(о.get("color_hex") or "").strip()
        own = None if _ВМ.невідомо(о.get("own")) else str(о.get("own")).strip()
        # `worn` false — модель сама каже «без цього слота»; відсутнє чи будь-що інше — річ носиться
        носить = not (о.get("worn") is False or str(о.get("worn")).strip().lower() == "false")
        вих.append(dict(назва=назва, деталі=" ".join(str(о.get("details") or "").split())[:160] or None,
                        слот=_слот_за_назвою(код), код_слота=код,
                        hex=(hx.lower() if _HEX.match(hx) else None), own=own, носить=носить))
    return вих or None


# Код `is_outfit` у записі моделі → код ядра: її запис коду (регістр, пробіл, булеве) приймається, як `worn`;
# слів тут нема — лише два коди схеми
_ОБРАЗ_КОДОМ = {"yes": True, "true": True, "no": False, "false": False}


def опис_образ(відповідь):
    """Чи опис руки — образ, кодом відповіді ПЕРЕЛІКУ (`is_outfit`): True, False або None — коду нема.

    Слів опису код не читає (п.12): відмову моделі («I cannot fulfill…») називає кодом модель
    переліку, яка опис читає. None — перелік не прочитано або не має `is_outfit`: образом опис ніхто не назвав."""
    об, _причина, _ = _ПР.розбір_останній(відповідь, ("is_outfit",))
    if об is None:
        try:
            об = _json.loads(re_огорожа(str(відповідь or "")))
        except ValueError:
            return None
    к = об.get("is_outfit") if isinstance(об, dict) else None
    return _ОБРАЗ_КОДОМ.get(str(к).strip().lower()) if к is not None else None


def re_огорожа(т):
    """Огородження ```json на КІНЦЯХ відповіді — геть; усередину код не заглядає."""
    return _re.sub(r"^\s*```(?:json)?\s*|\s*```\s*$", "", т)
