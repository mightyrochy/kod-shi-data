def придушення(темп_c):
    """K-OUT-01. Наскільки теплова функція забирає голос у правил пропорції й стану.

    Повертає None, коли температури НЕ ДАЛИ. Це не те саме, що 0.0: правило мовчить,
    а не вгадує. Тема каже прямо: «лише коли температура відома».
    """
    if темп_c is None:
        return None
    верх, низ = C["придушення_верх_c"], C["придушення_низ_c"]
    if темп_c >= верх:
        частка = 0.0
    elif темп_c <= низ:
        частка = 1.0
    else:
        частка = round((верх - темп_c) / (верх - низ), 2)
    return dict(
        частка=частка, темп_c=темп_c, поріг_верх=верх, поріг_низ=низ,
        чому=("нижче %+.0f°C теплова функція починає скасовувати правила пропорції, "
              "нижче %+.0f°C скасовує повністю" % (верх, низ)),
        статус="[конвенція]: поріг успадковано з температурної мапи корпусу, власного "
               "числа правило не має — джерела кажуть словами («sub zero», «frigid»)")


def придушення_знахідка(пр, придушених):
    """K-OUT-01 говорить ВЛАСНИМ голосом, а не лише позначкою на чужих знахідках.

    ЩО ЦЕ МІНЯЄ: тема вимагає, щоб придушення було СКАЗАНЕ ВГОЛОС («за такої
    температури довжина обрана по теплу, не по пропорції»). Позначка `придушено`
    всередині чужої знахідки цього не робить: людина бачить ослаблений рядок і не
    бачить ПРИЧИНИ. Тут причина стає окремим рядком з власним ID.
    """
    if not пр or not пр["частка"]:
        return []
    return [dict(_зн("K-OUT-01", "strong",
        "довжина й стан обрані ПО ТЕПЛУ, не по пропорції", ["образ"],
        "при %+.0f°C теплова функція скасовує правила пропорції на %.0f %%: %s. Це не "
        "помʼякшення їхньої сили, а зміна того, ЯКЕ правило взагалі має голос — "
        "балансувати тепло проти стилю доводиться, і якщо потрібне тепло, беруть "
        "довше, попри те, що довге «затопить» невисоку фігуру (Lamport); у мороз "
        "застібається все, що є (Derek Guy)"
        % (пр["темп_c"], пр["частка"] * 100,
           ", ".join(sorted({ПРИДУШУВАНІ[з["правило"]] for з in придушених}))
           or "жодне правило пропорції в цьому образі не спрацювало"),
        ламається="«певна температура» — порожнє місце: обидва джерела називають її "
                  "СЛОВАМИ («sub zero», «frigid»). %s" % пр["статус"],
        поріг=пр["поріг_верх"], вимір=пр["темп_c"]),
        сила_нп=пр["частка"],
        сила_нп_джерело="вимір: рампа між двома смугами температурної мапи корпусу")]


def _придушити(зн, пр):
    """Прикласти придушення до списку знахідок. Знахідка НЕ зникає — вона
    позначається, і сила падає. Зникнення сховало б, що система знає про пропорцію."""
    if not пр or not пр["частка"]:
        return зн
    ч = пр["частка"]
    вих = []
    for з in зн:
        if not isinstance(з, dict) or з.get("правило") not in ПРИДУШУВАНІ:
            вих.append(з); continue
        з = dict(з)
        стара = з.get("сила_нп")
        if стара is not None:
            з["сила_нп"] = round(стара * (1.0 - ч), 2)
        з["придушено"] = dict(
            правило="K-OUT-01", частка=ч, було=стара,
            чому="за %+.0f°C довжина й стан обираються ПО ТЕПЛУ, не по пропорції; "
                 "«%s» лишається в списку, щоб було видно, чим система поступилась"
                 % (пр["темп_c"], ПРИДУШУВАНІ[з["правило"]]))
        if ч >= 1.0:
            з["блокує"] = False
        вих.append(з)
    _СЛ.запис("K-OUT-01", "теплова функція придушує пропорцію", "придушення",
              значення="частка %.2f при %+.0f°C" % (ч, пр["темп_c"]), сила=ч,
              напрям="скасовує голос, не силу")
    return вих


