def теплова_функція(речі):
    """Скільки ТЕПЛОВИХ шарів дає верхній шар, і що він дає замість тепла.

    Повертає dict, а не список знахідок: це ВХІД для K-WEA-01, і споживач має
    дістати число, а не текст. Знахідки — окремо, у `перевірити`.

    ГРАДУСИ ЗВІДСИ ЗНЯТО (`темп_c` стояв у сигнатурі й не вживався,
    `аудит/КЛАС_МЕРТВІ_ПАРАМЕТРИ.md`): теплова функція — властивість РЕЧІ, а не погоди
    («ці значення не переводяться в градуси» нижче), і зважує її з температурою
    споживач — K-WEA-01 у `перевірити`, `придушення(темп_c)` у стані.
    """
    в = _верхній(речі)
    if в is None:
        return dict(є=False, тепловий_внесок=0.0,
                    чому="верхнього шару в образі нема")
    тип = в.get("тип_верхнього") or в.get("тип")
    функції = ТЕПЛОВІ_ФУНКЦІЇ.get(тип)
    if функції is None:
        return dict(є=True, річ=_імʼя(в), тип=тип, тепловий_внесок=1.0,
                    впевненість="низька",
                    чому="тип верхнього шару не розпізнано (%s) — внесок узято повним, "
                         "бо занижувати його без підстави означало б вигадати холод"
                         % (тип or "нема"))
    тепло, вітер, волога = функції
    внесок = _ТЕПЛО_ВАГА[тепло]
    ноти = []
    # ── K-OUT-18: частка вовни. ЄДИНИЙ поріг теми, який фід може перевірити ────
    вовна = в.get("вовна_частка")
    if вовна is not None:
        if вовна >= C["вовна_частка_мін"]:
            внесок = min(1.0, внесок + 0.2)
            ноти.append("склад оголошено: вовни %.0f %% (≥ %.0f %%) — K-OUT-18, "
                        "фольклорна константа, ранжувальний член, не гейт"
                        % (вовна * 100, C["вовна_частка_мін"] * 100))
        else:
            ноти.append("вовни %.0f %% — нижче за смугу 60–70 %% K-OUT-18; це не "
                        "вирок, це названий ранг" % (вовна * 100))
    elif тип in ("тренч", "плащ"):
        # K-OUT-20: «склад без вовни або не оголошений». Оголошена вовняна версія —
        # інший випадок, і саме тому склад питається, а не припускається.
        ноти.append("складу не оголошено; для тренча це вирішальне — вовняна версія "
                    "має зимову функцію, бавовняний габардин не має")
    # ── K-OUT-27: ОГОЛОШЕНЕ СЛОВО СКЛАДУ ЧИТАЄТЬСЯ, НАЗВА КАТЕГОРІЇ — НІ ──────
    нап = в.get("наповнювач")
    if нап is False:
        _був = внесок
        внесок = round(внесок * C["без_утеплювача_частка"], 2)
        ноти.append("магазин оголосив «без утеплювача»: тип «%s» обіцяє тепло, склад "
                    "його не несе — внесок %.2f → %.2f (K-OUT-27: слово поля означає "
                    "себе, тема-11:580; частка — константа реєстру, не градуси)"
                    % (тип, _був, внесок))
    elif нап == "пух":
        волога = _ВОЛОГА_ВНИЗ[волога]
        ноти.append("наповнювач оголошено словом: «пух». Мітка вологи стоїть на ТИПІ, "
                    "а мокне саме наповнювач — тема-11:508–510 зве режим, «у якому "
                    "пуховик мокне»; вісь вологи цього шару йде на крок нижче")
    elif isinstance(нап, str) and нап:
        ноти.append("наповнювач оголошено словом: «%s»%s. Тепловий внесок не "
                    "змінено: корпус не дає синтетиці ні переваги, ні програшу по "
                    "теплу проти пуху, і вигадувати рейтинг заборонено (K-OUT-15)"
                    % (нап, "" if нап in _СИНТЕТИЧНІ_НАПОВНЮВАЧІ else
                       " — слово поза словником `feed._НАПОВНЮВАЧІ`, лишається як є"))
    elif тип in ("пуховик", "куртка", "парка", "анорак", "жилет", "вітровка"):
        ноти.append("наповнювача не оголошено, а назва категорії його НЕ оголошує "
                    "(K-OUT-27): «пуховиком» звуть будь-яку куртку, і всередині може "
                    "бути пух або синтепон. Теплова мітка тут стоїть на типі — це "
                    "найслабше місце теплової осі, і воно назване, а не приховане")
    # ── K-OUT-38: оверсайз протікає рукавами й коміром ────────────────────────
    if в.get("оверсайз"):
        внесок = round(внесок * 0.8, 2)
        ноти.append("оголошений оверсайз: широкі рукави й відкриті коміри впускають "
                    "вітер (K-OUT-38) — більше тканини НЕ означає тепліше, і "
                    "рекомендувати оверсайз ЯК ТЕПЛОВЕ РІШЕННЯ заборонено")
    # ── K-OUT-17: простібка як ТАЙБРЕЙК, не як вхід ──────────────────────────
    if в.get("простібка"):
        ноти.append("наскрізна простібка: до %.0f %% втрати CLO проти коробчастих "
                    "перегородок (K-OUT-17). Це менше за різницю між двома розмірами "
                    "пуху, тож як окремий вхід воно шум — придатне лише як тайбрейк"
                    % (C["простібка_втрата_clo"] * 100))
    return dict(є=True, річ=_імʼя(в), тип=тип,
                тепло=тепло, вітер=вітер, волога=волога,
                тепловий_внесок=round(внесок, 2), ноти=ноти,
                чому="теплова функція розкладена на ТРИ осі, бо тренч і дублянка "
                     "закривають різні режими погоди, а K-WEA-02 має лише вісь тепла",
                межа="жодне з цих значень не є CLO. CLO — правильна міра, і її не "
                     "публікують (K-OUT-16); лофт вимірний і його теж не публікують "
                     "(K-OUT-47). Тут ЯКІСНІ мітки за типом виробу, і вони не "
                     "переводяться в градуси")


