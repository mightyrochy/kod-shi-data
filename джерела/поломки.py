def _сценарій(d):
    """Сценарій прогону з паспортом (той самий злиток, що бачать пул і суд)."""
    п = d.get("паспорт") if isinstance(d.get("паспорт"), dict) else {}
    сцен, _ = _ПН.з_показу(d.get("сценарій") or {}, п)
    return сцен


def вхід(запис, d, п=None):
    """Чи є правилу за що взятись у цьому прогоні: (True, None) | (False, «поле: чому»).

    `d` — вхід ендпойнта після `_застосувати_паспорт`; `п` — пакет палітри (`_пакет`).
    Брак входу названо ПОЛЕМ (аудит/ПРОДУКТ.md п.4) — воно йде в `поломка.без_входу`."""
    ід = запис["ід"]
    if ід == "R-COL-16":
        бік = ((п or {}).get("особа") or {}).get("бік_b") or {}
        return (True, None) if бік.get("вхід") else (False, "особа.бік_b.вхід: eyes_give_no_side")
    if ід == "K-BOD-02":
        о = d.get("обхвати") or {}
        return (True, None) if any(v for v in (о.values() if isinstance(о, dict) else ())) \
            else (False, "обхвати: none")
    сцен = _сценарій(d)
    if ід == "K-CRA-01":
        return (False, "сценарій.нагода: sport_or_home") if _СВМ.спорт_чи_дім(сцен) else (True, None)
    if ід == "K-KOH-02":
        смуга = _Ф.смуга_ошатності(сцен)
        if not смуга:
            return False, "сценарій.смуга_ошатності: none"
        return (True, None) if ціль_поломки_ошатності(смуга[:2]) else \
            (False, "сценарій.смуга_ошатності: no_adjacent_step")
    if ід == "K-OUT-33":
        # «накинуто» є в переліку станів лише без холодного придушення K-OUT-01 (при −8 °C і нижче
        # застібається все), і лише коли температура відома — так само мовчить `верхнє_погода.придушення`
        пр = _ВП.придушення(сцен.get("темп_c"))
        return (True, None) if пр and not пр["частка"] \
            else (False, "сценарій.темп_c: none_or_cold_suppresses_draped")
    if ід in ("K-SIL-03", "K-FIT-03"):
        # тіло T будується лише з трьох обхватів і більше (`міст_вхід._збірка`); без нього
        # ні обгортки силуету, ні зон краю нема
        о = d.get("обхвати") or {}
        return (True, None) if sum(1 for v in (о.values() if isinstance(о, dict) else ()) if v) >= 3 \
            else (False, "обхвати: fewer_than_3")
    if ід == "K-SHO-16":
        # без тривалості й поверхні `вартість_носіння` дає лише питання K-END-01
        return (True, None) if (сцен.get("тривалість_год") or сцен.get("поверхня")) \
            else (False, "сценарій.тривалість_год|поверхня: none")
    if ід == "K-PAL-18":
        розв = ((п or {}).get("палітри") or {}).get("розвилка") or []
        є = any(isinstance(сп, dict) and сп.get("роль") == "акцент" and сп.get("C")
                for г in розв for сп in (((г or {}).get("спец") or {}).get("слоти") or {}).values())
        return (True, None) if є else (False, "палітри.розвилка: no_accent_role")
    if ід == "R-MUA-02":
        # та сама функція, що вирішує рядок брифа руки 1 і тему розмови: вони не розходяться
        return (True, None) if _Б.порада_з_випадку(((п or {}).get("особа") or {}).get("рівень"), сцен) \
            else (False, "сценарій.макіяж: no_makeup_advice_applies")
    if ід == "K-MAT-03":
        return (True, None) if сцен.get("темп_c") is not None else (False, "сценарій.темп_c: none")
    if ід == "K-COL-06-M":
        о = (п or {}).get("особа") or {}
        є = (d.get("самозвіт") or {}).get("метал") or сцен.get("прикраси") \
            or ((о.get("температура") or {}).get("придатно"))
        return (True, None) if є else (False, "метал: no_self_report_no_jewellery_wish_no_undertone")
    return True, None


def _лише_суд(ід):
    """Правило діє лише в суді: у `місця` нема ні пулу, ні промпту (взуття, схема)."""
    return not ({"pool", "prompt"} & set(ЗА_ІД[ід]["місця"]))


def жереб(d, п=None, перелік=ПЕРЕЛІК, діє=None, пар=None):
    """Правила, які рука 2 вимикає в цьому прогоні: (запис, доступні ід, без_входу {ід: чому}, пара).

    `запис` — злиток (`злити`) від 1 до `межа_поломок` правил на різних аспектах, зважених на
    брак людських пар (`пар`, типово `ЛЮДСЬКИХ_ПАР`).

    Лише з тих, що мають вхід; сід прогону +11 — жереб відтворюваний.
    `діє` — {ід: місця}, де правило ДІЄ на цьому прогоні (`дія_правил`: тінь пакета руки 1
    під стеженням за всіма кодами переліку + рядки брифа руки 1). З ним жереб бере РІВНО
    з правил з входом, що діють у пулі АБО в промпті, і лише коли нема
    жодного — будь-яке з входом; `пара` каже, де діє випале: {"дія": pool | prompt_only |
    judge | empty, "чому": None | поле}. `judge` — правило, що діє ЛИШЕ в
    суді (`місця` без pool і prompt: взуття, схема): суд руки 1 видно тільки після відповіді
    моделі, тож воно входить у жереб нарівні, а чи справді спрацювало — каже `правило_діяло`. `empty` — пара чесно порожня: руки 1 і 2 дістали той самий пул і
    промпт, і звіт називає причину полем, а не мовчить (аудит/ПРОДУКТ.md п.4).
    Без `діє` (None) кандидати — усі з входом."""
    дост, без = [], {}
    for з in перелік:
        є, чому = вхід(з, d, п)
        (дост.append(з["ід"]) if є else без.__setitem__(з["ід"], чому))
    пара = dict(дія=None, чому=None)
    ламкі = [ід for ід in дост if ід not in ПОЗА_ЖЕРЕБОМ]
    if діє is None:
        пул = sorted(ламкі)
    else:
        # РІВНО: ярус «спершу пул» майже завжди має кандидата (K-KOH-02 і рядок металу діють у
        # пулі на кожному прогоні з нагодою й палітрою), і правила лише промпту не випадали б
        # ніколи. Жива модель бачить інший промпт — це вже інший образ.
        # Правила лише суду не мають рядка брифа й тіні пулу, тож `діє` їх не
        # бачить; суд руки 1 відомий лише після відповіді моделі — вони входять нарівні, а чи
        # спрацювали, скаже звіт (`правило_діяло`). Промпт руки 1 при цьому не міняється.
        пул = sorted(ід for ід in ламкі if діє.get(ід) or _лише_суд(ід))
        if not пул:
            пул = sorted(ламкі)
            пара = dict(дія="empty", чому=("rules: none_has_input" if not ламкі
                                           else "pool_prompt: no_rule_with_input_acts"))
    пул = пул or sorted(з["ід"] for з in перелік if з["ід"] not in ПОЗА_ЖЕРЕБОМ)
    за_ід = {з["ід"]: з for з in перелік}
    # СКІЛЬКИ ПОЛОМОК (нуля нема — тест потребує поломок): k рівно
    # з 1…стільки, скільки різних аспектів мають кандидати; кожна поломка — на іншому аспекті, щоб
    # скаргу на аспект було з чим зіставити. ЯКІ ПРАВИЛА: з усіх кандидатів, зважено на
    # брак людських пар (`ЛЮДСЬКИХ_ПАР`), без черги; генератор — сід прогону +11.
    рнд = _r.Random(int(d.get("сід") or 0) + ЗСУВ_СІДА)
    k = рнд.randint(1, межа_поломок(пул, перелік))
    пар = ЛЮДСЬКИХ_ПАР if пар is None else пар
    лишок, обрано = list(пул), []
    while лишок and len(обрано) < k:
        ід = рнд.choices(лишок, weights=[1.0 / (1 + пар.get(і, 0)) for і in лишок])[0]
        обрано.append(ід)
        лишок = [і for і in лишок if _група(за_ід[і]) != _група(за_ід[ід])]
    if діє is not None and пара["дія"] is None:
        пара = dict(дія=("pool" if any("pool" in діє.get(і, ()) for і in обрано)
                         else "prompt_only" if any(діє.get(і) for і in обрано) else "judge"), чому=None)
    return злити([за_ід[і] for і in sorted(обрано)]), sorted(дост), (без or None), пара


def _група(запис):
    """Аспект правила в жеребі; правило без аспекту (R-MUA-02) — своя група."""
    return запис.get("аспект") or запис["ід"]


def межа_поломок(ідс, перелік=ПЕРЕЛІК):
    """Скільки поломок може бути в прогоні: різних аспектів серед кандидатів `ідс`."""
    за_ід = {з["ід"]: з for з in перелік}
    return max(1, len({_група(за_ід[і]) for і in ідс if і in за_ід}))


def злити(записи):
    """Кілька правил переліку — одним записом тієї самої форми: `ід` і `тема` через «+»,
    коди, ключі брифа, місця й слоти — об'єднанням; `правила` — ID по одному, `поломок` — скільки,
    `аспект` — аспекти по правилах (None — без аспекту). Місця дії (`прогін`, пакет руки 2,
    `ключі_брифа_для`, тінь) беруть набір кодів, тож ламають усі правила разом."""
    раз = lambda поле: tuple(dict.fromkeys(х for з in записи for х in з[поле]))
    return dict(тема="+".join(з["тема"] for з in записи), ід="+".join(з["ід"] for з in записи),
                коди=раз("коди"), бриф=раз("бриф"), слоти=раз("слоти"),
                місця=tuple(м for м in ("pool", "judge", "prompt") if any(м in з["місця"] for з in записи)),
                вхід=" | ".join(з["вхід"] for з in записи), аспект=tuple(з["аспект"] for з in записи),
                правила=tuple(з["ід"] for з in записи), поломок=len(записи))


# Усі коди переліку: за ними стежить пакет руки 1 (`міст_запити._дія_правил`), щоб тінь пулу
# сказала, які правила на цьому прогоні діють. Константа, а не вибране правило: пакет руки 1
# кешується за входами (`міст_пакет._входи_пакета`), тож його тінь мусить бути та сама, хоч би
# хто й з яким жеребом збудував його першим.
УСІ_КОДИ = tuple(sorted({к for з in ПЕРЕЛІК for к in з["коди"]}))


def дія_правил(тінь_пулу=(), ключі_брифа=(), перелік=ПЕРЕЛІК):
    """{ід: [місця]} — де кожне правило переліку ДІЄ на цьому прогоні руки 1.

    `тінь_пулу` — тінь пакета руки 1 під стеженням за `УСІ_КОДИ` (місця pool, witness,
    prompt пакета); `ключі_брифа` — коди рядків брифа руки 1 (`бриф["правила"][].код`).
    Свідок (`witness`, R-COL-16) — дія в пулі: він переставляє ранг основ і ключ сортування.
    Рядок задачі складання, що належить правилу (`пакет_моделі.РЯДКИ_ЗАДАЧІ_ЗА_ПРАВИЛОМ`), —
    дія в промпті. Правила, що діють лише в суді, тут не видно: суд бачить образ, а образу
    до відповіді моделі нема."""
    кл = set(ключі_брифа or ())
    вих = {}
    for з in перелік:
        наб = frozenset(з["коди"])
        м = {("pool" if т.get("де") == "witness" else т.get("де")) for т in (тінь_пулу or ())
             if _у(т.get("правило"), наб)}
        if кл & set(ключі_брифа_для(з["коди"])) or наб & set(_ПМ.РЯДКИ_ЗАДАЧІ_ЗА_ПРАВИЛОМ):
            м.add("prompt")
        м.discard(None)
        if м:
            вих[з["ід"]] = sorted(м)
    return вих


def _речі_пулу(пак):
    """Речі пулу пакета: {(слот, назва, ціна)}; None — пулу нема (прогін без каталогу)."""
    пул = ((пак or {}).get("пакет") or {}).get("пул")
    if not isinstance(пул, dict):
        return None
    return {(сл, р.get("назва"), р.get("ціна")) for сл, рр in пул.items() for р in (рр or [])}


def різниця_пулів(пак_1, пак_2):
    """Скільки речей пулу руки 2 нема в пулі руки 1 і навпаки (речі — слот, назва, ціна).

    Тінь каже, що правило ТОРКНУЛОСЬ пулу; ця лічба — чи пул від того став іншим. Рядок
    металу палітри (K-PAL-11) торкається пулу щоразу, а речей міняє одну-дві з 400, і
    заглушка стенда, що бере k-ту річ кожного слота, складає тоді той самий образ.
    None — пулу нема (прогін без каталогу)."""
    а, б = _речі_пулу(пак_1), _речі_пулу(пак_2)
    return None if а is None or б is None else len(а ^ б)


def різниця_по_слотах(пак_1, пак_2):
    """Ті самі речі, що в `різниця_пулів`, але по слотах: {слот: скільки} лише слоти, де пул руки 2
    різниться: звіт пари каже, КУДИ правило пулу зсунуло добір, а не лише скільки.
    Порожній словник — пули збігаються; None — пулу нема."""
    а, б = _речі_пулу(пак_1), _речі_пулу(пак_2)
    if а is None or б is None:
        return None
    вих = {}
    for сл, _, _ in (а ^ б):
        вих[сл] = вих.get(сл, 0) + 1
    return dict(sorted(вих.items()))


def слоти_рядком(різниця):
    """Різницю по слотах кодовим рядком звіту: «слот:n,слот:n»; none — пули збігаються; None → None."""
    return None if різниця is None else (",".join("%s:%d" % (сл, n) for сл, n in різниця.items()) or "none")


def різниця_промптів(пак_1, пак_2):
    """Чи текст пакета руки 2 інший за текст пакета руки 1 : True | False;
    None — одного з пакетів нема (прогін без каталогу). Пакет несе і пул, і рядки брифа, і
    `coat_required`, тож різниця тут — це все, що правило змінило у вході моделі.
    ПОРЯДОК РЕЧЕЙ НЕ РАХУЄТЬСЯ: рука 2 показує ті самі речі своїм сідом, тож текст
    різниться завжди; склад пулу міряє `різниця_пулів`, тут — пакет без пулу."""
    import json as _j
    а, б = [((п or {}).get("текст"), (п or {}).get("пакет")) for п in (пак_1, пак_2)]
    if not all(isinstance(т, str) and т for т, _ in (а, б)):
        return None
    if not all(isinstance(пк, dict) for _, пк in (а, б)):
        return а[0] != б[0]
    без_пулу = lambda пк: _j.dumps({к: в for к, в in пк.items() if к != "пул"}, sort_keys=True,
                                    ensure_ascii=False, default=str)
    return без_пулу(а[1]) != без_пулу(б[1])


def ярус_виміряно(пара, пул_різниця, промпт_різний, місця):
    """Ярус пари ЗА ВИМІРЯНИМ входом руки 2, а не за тінню: `pool` — пул руки 2
    справді інший; `prompt_only` — пул той самий, інший пакет (`coat_required`, рядок брифа);
    `judge` — вхід моделі той самий, різниця може бути лише в суді. `дія_тінь` — що казала тінь
    жеребу (правило ТОРКАЄТЬСЯ пулу ≠ пул змінився). Нічого не виміряно (нема каталогу) або пара
    порожня з жеребу — без змін."""
    п = dict(пара or {})
    if п.get("дія") == "empty" or (пул_різниця is None and промпт_різний is None):
        return п
    п["дія_тінь"] = п.get("дія")
    if пул_різниця:
        п["дія"] = "pool"
    elif промпт_різний:
        п["дія"] = "prompt_only"
    elif "judge" in (місця or ()):
        п["дія"] = "judge"
    else:
        п["дія"], п["чому"] = "empty", "pool_prompt: measured_no_input_diff"
    return п


def виміряти_пару(поломка, пак_1, пак_2, частин=(1, 1)):
    """Одним місцем для `запити` і `від_моделі` : що правило змінило
    у вході руки 2 порівняно з рукою 1 — полями `поломка` й кодовим рядком журналу `що_змінено`.

    Поля рядка: `pool_diff`, `pool_diff_slots`; `prompt_diff` (пакет інший: 1|0|unknown);
    `input_diff` = none | pool | prompt | pool+prompt | unknown; `pair_measures` — що міряє пара:
    при `input_diff=none` рука 2 складена з того самого пулу й промпту (правило лише суду), тож картки різняться шумом моделі плюс судом; `parts` = частин пулу руки 1 / руки 2
    (з `частин` > 1 пул руки 1 збирається на кілька бюджетів, а рука 2 на один).
    `pair=` у рядку — виміряний ярус; жеребова тінь — у `пара.дія_тінь`."""
    пул, слоти, пром = різниця_пулів(пак_1, пак_2), різниця_по_слотах(пак_1, пак_2), різниця_промптів(пак_1, пак_2)
    поломка.update(пул_різниця=пул, пул_різниця_слоти=слоти, промпт_різниця=пром)
    рекомендації = [т for т in (пак_2 or {}).get("тінь_руки_2") or [] if "правильна" in т]
    if рекомендації:
        поломка["рекомендації"] = рекомендації
    поломка["пара"] = ярус_виміряно(поломка.get("пара"), пул, пром, поломка.get("місця"))
    п = поломка["пара"]
    зм = [] if пул is None and пром is None else [("pool" if пул else None), ("prompt" if пром else None)]
    вхід = "unknown" if пул is None and пром is None else ("+".join(х for х in зм if х) or "none")
    хвіст = ["pool_diff=%s" % пул, "pool_diff_slots=%s" % слоти_рядком(слоти),
             "prompt_diff=%s" % ("unknown" if пром is None else int(пром)), "input_diff=" + вхід,
             "pair_measures=" + {"none": "judge+model_noise", "unknown": "unknown"}.get(вхід, "input+judge+model_noise"),
             "parts=%d/%d" % tuple(частин)]
    сегм = [("pair=%s%s" % (п.get("дія") or "unknown", (":" + п["чому"]) if п.get("чому") else ""))
            if с.startswith("pair=") else с for с in поломка["що_змінено"].split(" · ")]
    поломка["що_змінено"] = " · ".join(сегм + хвіст)
    поломка["пара_виміряно"] = " · ".join(хвіст)      # той самий хвіст — у `пара_руки` звіту
    return поломка


