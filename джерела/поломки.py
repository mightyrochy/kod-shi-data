# ── K-FIT-03: КРАЙ НА НАЙШИРШОМУ МІСЦІ ──────────────────────────────────────────
# Параметр — знак: справне радить край геть з опуклості зони, зламане — край у її найширшу точку.
def _краї_навпаки(зн, проф, речі):
    """Справна порада — у тінь; річ із краєм ПОЗА опуклістю, коли у вікні зсуву є найширша точка зони,
    дістає ремонт «край у цю точку». Питання (довжини нема, смуга слова торкається опуклості) лишаються."""
    вих, судила = [], set()
    for з in зн:
        if з.get("правило") == "K-FIT-03" and з.get("сила") != "питання":
            з = _придушити(з, "edge_off_widest", "edge_on_widest")
        if з.get("правило") == "K-FIT-03":
            судила |= {str(х) for х in з.get("речі") or ()}
        вих.append(з)
    for р in речі:
        if str(р["id"]) in судила or р.get("край_джерело") == "дефолт слота":
            continue
        if р.get("слот") == "взуття" and _ФІТ.край(р) <= 1.0:
            continue
        m = _ФІТ.край_проти_локального(проф, _ФІТ.край(р))
        лок = m["локальний_максимум"]
        if лок is None or m["на_максимумі"]:
            continue
        ціль = [[round(лок["см"] - 1.0, 1), round(лок["см"] + 1.0, 1)]]
        вих.append(_хибна_знахідка("K-FIT-03", [р], "edge_off_widest",
                                   dict(level=лок["рівень"], cm=лок["см"]), "move_edge_to_widest",
                                   _ВМ.заява("move_edge_to_cm", ranges=ціль)))
    return вих


