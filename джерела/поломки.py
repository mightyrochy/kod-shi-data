def підпис_тестувальниці(д, п, в):
    """Ід тестувальниці — підпис профілю, не пристрій. `тестувальниця` пише новий показ; у давніх
    файлах це `профіль`, якщо він не типове «безіменна». Нема підпису — None («невідомо»), за пристроєм не вгадують."""
    сп = dict(д.get("спільне") or {}, **(п.get("спільне") or {}))
    for к in ("тестувальниця", "профіль"):
        з = str(в.get(к) or сп.get(к) or "").strip()
        if з and з not in БЕЗ_ПІДПИСУ and "Проба РВ-6" not in з: return з
    return "Проба РВ-6" if "Проба РВ-6" in str(в.get("профіль") or сп.get("профіль") or "") else None


def запис_пари(д, п):
    """Запис пари рук 1↔2 одного прогону файла вердиктів `д` (прогін `п`); None — вердиктів рук 1–2 у прогоні нема."""
    вв = {str(в.get("рука")): в for в in п.get("вердикти") or []}
    if not ({"1", "2"} & set(вв)): return None
    в1, в2 = вв.get("1") or {}, вв.get("2") or {}
    сп = dict(д.get("спільне") or {}, **(п.get("спільне") or {}))
    оцінено = {к: (вв.get(к) or {}).get("вердикт_людини") in ОЦІНКИ_РУК for к in ("1", "2")}
    пропуск = {(True, True): None, (False, True): "рука 1 без вердикту", (True, False): "рука 2 без вердикту"}.get((оцінено["1"], оцінено["2"]), "обидві руки без вердикту")
    для = lambda в: bool(в.get("для_мене"))
    return {"прогін": п.get("прогін"), "прогін_ід": сп.get("прогін"), "пристрій": д.get("пристрій"),
            "тестувальниця": підпис_тестувальниці(д, п, в2 or в1),
            "стенд": "Проба РВ-6" in str(сп.get("профіль")),
            "жереб": {"пара": в2.get("пара_руки") or None, "поломка": в2.get("поломка_руки") or None},
            "зламані_місця": [і for і in str(в2.get("правило_руки") or "").split("+") if і] if в2.get("поломка_руки") == "rule_off" else [],
            "правило_без_поломки": [і for і in str(в1.get("правило_руки") or "").split("+") if і],
            "картки": {"1": в1 or None, "2": в2 or None}, "оцінено": оцінено, "вісь_для_мене": {"1": для(в1), "2": для(в2)},
            "повна": not пропуск, "пропуск": пропуск}
