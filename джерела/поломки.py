    відомі = []
    for r in речі:
        п = _хибний_щабель(_Ф.інтервал_формальності(r), смуга, ціль)
        if п is not None:
            відомі.append((str(r.get("id")), п, id(r)))
    if відомі:
        _рекомендація("K-KOH-02", "pool", list(смуга), list(ціль), "filter_neighbor_step",
                      речі=[і for і, лишилась, _ in відомі if not лишилась],
                      збережено=[і for і, лишилась, _ in відомі if лишилась])
    return frozenset(о for _, лишилась, о in відомі if not лишилась)


