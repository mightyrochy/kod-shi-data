# ── K-KOH-02: СМУГА ОШАТНОСТІ НА ЩАБЕЛЬ ПОЗА НАГОДОЮ ──────────────────────────
# Ціль поломки й крок — `формальність.ціль_поломки_ошатності` (3.3: її читає й бриф, нижчий за поломки).
def _хибний_щабель(інтервал, справна, ціль):
    """True: відомий інтервал досягає хибного щабля й цілком поза справною смугою; невідомий — None."""
    lo, hi = інтервал
    if lo is None or hi is None or ціль is None:
        return None
    return lo <= ціль[0] <= hi and (hi < справна[0] or lo > справна[1])


def _смуга_ошатності(смуга):
    return ціль_поломки_ошатності(смуга) or смуга


