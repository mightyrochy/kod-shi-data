# -*- coding: utf-8 -*-
"""РІЗАК ФІДУ: великий YML магазину → український жіночий підфід у діалекті проєкту.

ЧОМУ ЦЕ ІСНУЄ (фейл-кейс, не зручність). Живі фіди українських магазинів важать
30–200 МБ і 30 тис. SKU. Жоден чат їх не проковтне: у сесії Ager фід довелось
качати телефоном, зіпувати, заливати назад — і нарізали його РУКАМИ, через що в
журналі стоїть «поля обрізані». Обрізані поля означають, що частина шару даних
померла тихо: `feed.читати_yml` читає param «Колір», picture, article, stock —
і кожне втрачене поле вимикає цілий шар правил нижче за течією без жодної помилки.

ЩО ЦЕ МІНЯЄ В РІШЕННІ. Після прогону видно ОДНЕ число, яким вирішується доля
магазину: частка товарів, де код МОЖЕ прочитати колір. Магазин із покриттям 0.9
йде в роботу; магазин із 0.05 не йде взагалі, і на нього не витрачається сесія.

МОВНИЙ ГЕЙТ СТОЇТЬ НА ВХОДІ, а не в голові. Тверде правило проєкту — джерела
лише українською. Досі воно трималось дисципліною, і одного разу вже зламалось
(фід Ager, російський, взятий як разовий виняток). Тут російський фід не
проходить механічно.

Вжиток (працює всередині ChatGPT / Gemini / Claude, без мережі):
    python3 підфід.py фід.xml
    python3 підфід.py фід.xml.gz --вихід магазин.xml --макс 4000
    python3 підфід.py фід.zip --мова звіт        # не блокувати, лише сказати
"""
import sys, os, io, gzip, zipfile, re, datetime
import xml.etree.ElementTree as ET

# ── лексикон кольорів ───────────────────────────────────────────────
# ЄДИНЕ ДЖЕРЕЛО — `verify.ЛЕКСИКОН`. Копія нижче потрібна лише тоді, коли різак
# запускають окремо від решти модулів; у звіті прямо сказано, яка гілка спрацювала,
# бо розбіжність копії з оригіналом зробила б покриття брехливим.
_КОПІЯ = ("бежевий блакитний бордовий бузковий білий вершковий вишневий графіт "
          "гірчичний жовтий зелений золотий кемел коричневий лимонний м'ятний "
          "молочний оливковий персиковий помаранчевий пудровий пісочний рожевий "
          "синій срібний сірий темно-синій теракотовий фіолетовий хакі червоний "
          "чорний шоколадний").split()
try:
    import verify as _V
    ЛЕКСИКОН, ДЖЕРЕЛО_ЛЕКС = sorted(_V.ЛЕКСИКОН), "verify.ЛЕКСИКОН"
except Exception:
    ЛЕКСИКОН, ДЖЕРЕЛО_ЛЕКС = _КОПІЯ, "вбудована копія (verify недоступний)"

# ── мова ────────────────────────────────────────────────────────────
# Розрізнювач грубий і чесно грубий: букви, яких нема в другій мові, плюс
# кілька частотних слів товарних назв.
# КОЛИ ДІЄ: на кириличних назвах довжиною від кількох слів.
# ДЕ ЛАМАЄТЬСЯ: назви суцільною латиницею («Dress Zara 1077»), суржик, і
# фіди, де українською лише категорії. Тому третій вихід — «невизначено», і
# він НЕ вважається українською.
_РОС_БУКВИ = re.compile(r"[ыъэё]")
_УКР_БУКВИ = re.compile(r"[іїєґ]")
_РОС_СЛОВА = re.compile(r"\b(женск|цвет|платье|юбка|рубашка|брюки|кофта|"
                        r"размер|белый|черный|серый|синий|зеленый)", re.I)
_УКР_СЛОВА = re.compile(r"\b(жіноч|колір|кольор|сукня|спідниц|сорочк|штани|"
                        r"розмір|білий|чорний|сірий|зелений)", re.I)


def мова(тексти):
    рос = укр = 0
    for t in тексти:
        рос += len(_РОС_БУКВИ.findall(t)) + 2 * len(_РОС_СЛОВА.findall(t))
        укр += len(_УКР_БУКВИ.findall(t)) + 2 * len(_УКР_СЛОВА.findall(t))
    усього = рос + укр
    if усього < 5:
        return "невизначено", dict(рос=рос, укр=укр, сигналу="замало")
    частка = укр / усього
    висновок = ("українська" if частка >= 0.8 else
                "російська" if частка <= 0.2 else "мішана")
    return висновок, dict(рос=рос, укр=укр, частка_укр=round(частка, 3))


# ── жіночий одяг ────────────────────────────────────────────────────
_ЖІНОЧЕ = re.compile(r"(жіноч|сукн|спідниц|блуз|сорочк|штан|джинс|футболк|"
                     r"светр|кардиган|жакет|пальт|куртк|плащ|тренч|топ|боді|"
                     r"комбінезон|костюм|туфл|черевик|босоніж|балетк|лофер|"
                     r"кросівк|сумк|шарф|хустк|ремін)", re.I)


def _жіноче(назва, категорія):
    return bool(_ЖІНОЧЕ.search(назва) or _ЖІНОЧЕ.search(категорія))


# ── колір у назві ───────────────────────────────────────────────────
_ТОКЕН = re.compile(r"[а-яіїєґА-ЯІЇЄҐ'\-]{3,}")


def колір_у_тексті(текст):
    """Слово кольору, яке лексикон коду ЗДАТЕН прочитати, або None.

    Збіг за префіксом у 4 літери в обидва боки: фід пише «беж», лексикон знає
    «бежевий»; фід пише «шоколад», лексикон — «шоколадний».
    ДЕ ЛАМАЄТЬСЯ: «білизна» ловиться на «білий» (спільний префікс «біли»).
    Тому це ОЦІНКА покриття, не вимір кольору; колір далі однаково міряє feed.py.
    """
    for сир in _ТОКЕН.findall(текст.lower()):
        for сл in ЛЕКСИКОН:
            if сир[:4] == сл[:4] or сир == сл:
                return сл
    return None


# ── читання будь-якої обгортки ──────────────────────────────────────
def відкрити(шлях):
    низ = шлях.lower()
    if низ.endswith(".gz"):
        return gzip.open(шлях, "rb"), "gzip"
    if низ.endswith(".zip"):
        z = zipfile.ZipFile(шлях)
        імена = [n for n in z.namelist() if n.lower().endswith((".xml", ".yml"))]
        if not імена:
            raise SystemExit("у zip нема .xml — усередині: %s" % z.namelist()[:5])
        return z.open(імена[0]), "zip:%s" % імена[0]
    return open(шлях, "rb"), "xml"


ПОЛЯ = ("name", "price", "currencyId", "categoryId", "url", "vendor",
        "article", "stock_quantity", "quantity_in_stock")

# ── СКІЛЬКИ ФОТО ЗАЛИШАТИ (08.09.2026) ──────────────────────────────
# ТУТ СТОЯЛО `фото[:1]`, І ЦЕ БУЛА РІВНО ТА ХВОРОБА, ПРО ЯКУ ПОПЕРЕДЖАЄ
# ДОКСТРІНГ ЦЬОГО Ж ФАЙЛУ: «кожне втрачене поле вимикає цілий шар правил нижче
# за течією без жодної помилки». Два споживачі нижче за течією прямо оголошують,
# що їм потрібно більше за одне фото:
#   · `bridge.ФОТО_НА_РІЧ = 2` — «перші два з фіду» їдуть у виклик опису, і саме
#     там модель пише те, що жінка читає поруч із фото;
#   · `pipeline.запит_приміряння` бере ПЕРШЕ НЕ-СМІТТЄВЕ фото (свотчі 50×50,
#     спінери, службова графіка теми) — у деяких магазинів справжнє фото стоїть
#     другим, і з одним збереженим річ мовчки йде в `без_фото`.
# Отже різак, який лишає одне, вимикав опис і приміряння на кожному такому SKU,
# а звіт при цьому рахував `покриття_фото` ДО зрізу — тобто називав 0.9 там, де
# в записаному підфіді був свотч.
# Число береться з `bridge`, а не вписується сюди: два джерела істини на одне
# число розійшлися б рівно так само тихо, як розійшлись би поля.
try:
    import bridge as _B
    ФОТО_НА_ОФЕР, ДЖЕРЕЛО_ФОТО = max(2, int(_B.ФОТО_НА_РІЧ)), "bridge.ФОТО_НА_РІЧ"
except Exception:
    ФОТО_НА_ОФЕР, ДЖЕРЕЛО_ФОТО = 3, "вбудоване (bridge недоступний): 2 на опис + 1 запас на свотч"


def прогін(шлях, вихід=None, макс=5000, режим_мови="строго"):
    потік, обгортка = відкрити(шлях)
    кат, offers = {}, []
    усього = жін = з_кольором = з_фото = 0
    зразок_назв = []

    # iterparse: фід на 200 МБ не влазить у пам'ять телефона й пісочниці цілком
    for подія, ел in ET.iterparse(потік, events=("end",)):
        тег = ел.tag.split("}")[-1]
        if тег == "category":
            кат[ел.get("id")] = ((ел.text or "").strip(), ел.get("parentId"))
            continue
        if тег != "offer":
            continue
        усього += 1
        назва = (ел.findtext("name") or ел.findtext("n") or "").strip()
        cid = ел.findtext("categoryId")
        шлях_кат, c, стеж = [], cid, set()
        while c and c in кат and c not in стеж:
            стеж.add(c); шлях_кат.append(кат[c][0]); c = кат[c][1]
        катшлях = " / ".join(reversed(шлях_кат))
        if len(зразок_назв) < 400 and назва:
            зразок_назв.append(назва + " " + катшлях)
        if _жіноче(назва, катшлях):
            жін += 1
            парам = {(p.get("name") or "").lower(): (p.text or "") for p in ел.findall("param")}
            текст_кольору = " ".join([назва] + [v for k, v in парам.items()
                                                if "колір" in k or "цвет" in k or "color" in k])
            кол = колір_у_тексті(текст_кольору)
            з_кольором += bool(кол)
            фото = [p.text for p in ел.findall("picture") if p.text]
            з_фото += bool(фото)
            if len(offers) < макс:
                offers.append(dict(
                    id=ел.get("id"), group_id=ел.get("group_id"),
                    available=ел.get("available"),
                    поля={t: ел.findtext(t) for t in ПОЛЯ if ел.findtext(t)},
                    фото=фото[:ФОТО_НА_ОФЕР],
                    парам=[(p.get("name"), p.text) for p in ел.findall("param")
                           if p.get("name") and p.text],
                    катшлях=катшлях, cid=cid))
        ел.clear()

    висн_мови, деталі = мова(зразок_назв)
    домен = ""
    for o in offers[:20]:
        u = o["поля"].get("url") or ""
        if u.startswith("http"):
            домен = u.split("/")[2]; break

    звіт = dict(файл=os.path.basename(шлях), обгортка=обгортка, домен=домен,
                офферів=усього, жіночих=жін, взято=len(offers),
                мова=висн_мови, мова_деталі=деталі,
                покриття_кольору=round(з_кольором / жін, 3) if жін else 0.0,
                покриття_фото=round(з_фото / жін, 3) if жін else 0.0,
                # ЩО САМЕ ЗАПИСАНО, а не що було у фіді: `покриття_фото` рахується
                # ДО зрізу, і сам по собі воно нічого не каже про підфід
                фото_на_офер=ФОТО_НА_ОФЕР, фото_межа=ДЖЕРЕЛО_ФОТО,
                фото_записано=sum(len(o["фото"]) for o in offers),
                офферів_з_одним_фото=sum(1 for o in offers if len(o["фото"]) == 1),
                лексикон=ДЖЕРЕЛО_ЛЕКС)

    друк_звіту(звіт)
    if висн_мови != "українська" and режим_мови == "строго":
        print("\n✗ ВІДМОВА: тверде правило проєкту — джерела лише українською.")
        print("  Фід не записано. Якщо магазин має український варіант каталогу —")
        print("  беріть його; якщо ні — магазин не придатний, і це результат.")
        print("  Обійти свідомо: --мова звіт (і тоді причина має лягти в журнал).")
        return звіт, None

    вихід = вихід or (re.sub(r"[^a-z0-9]+", "_", (домен or звіт["файл"]).lower()).strip("_") + ".xml")
    записати(вихід, звіт, offers, кат)
    print("\n✓ Записано: %s (%d офферів)" % (вихід, len(offers)))
    if жін > len(offers):
        print("  ⚠ ОБРІЗАНО: %d жіночих знайдено, %d взято (--макс). Решта втрачена,"
              % (жін, len(offers)))
        print("    і це не «вибірка» — це перші N у порядку фіду.")
    print("\nРядок для journal.tsv:")
    print("\t".join([домен or "?", обгортка, шлях, str(datetime.date.today()),
                     str(len(offers)),
                     "ВЗЯТО: жіночий підфід; колір %.2f, фото %.2f, мова %s"
                     % (звіт["покриття_кольору"], звіт["покриття_фото"], висн_мови)]))
    return звіт, вихід


def друк_звіту(з):
    print("═" * 66)
    print("ПІДФІД · %s (%s)" % (з["файл"], з["обгортка"]))
    print("═" * 66)
    print("домен: %s" % (з["домен"] or "—"))
    print("офферів усього: %d · жіночий одяг: %d · взято: %d"
          % (з["офферів"], з["жіночих"], з["взято"]))
    print("мова назв: %s %s" % (з["мова"].upper(), з["мова_деталі"]))
    print("покриття КОЛЬОРУ (лексикон коду, %s): %.2f" % (з["лексикон"], з["покриття_кольору"]))
    print("покриття ФОТО: %.2f (у фіді); записано %d знімків, до %d на офер — межа з %s; "
          "офферів з одним фото: %d"
          % (з["покриття_фото"], з.get("фото_записано", 0), з.get("фото_на_офер", 1),
             з.get("фото_межа", "?"), з.get("офферів_з_одним_фото", 0)))
    print("\nЯК ЧИТАТИ: покриття кольору — єдине число, яким вирішується доля")
    print("магазину. Нижче ~0.3 колірна вісь на цьому каталозі сліпа, і глибоко")
    print("качати його не варто. Фото важать менше: код уміє брати колір зі слова")
    print("(T3, впевненість 0.35), але фото дало б вимір замість слова.")


def main():
    арг = [a for a in sys.argv[1:] if not a.startswith("--")]
    if not арг:
        raise SystemExit(__doc__)
    def оп(імя, зам=None):
        return sys.argv[sys.argv.index(імя) + 1] if імя in sys.argv else зам
    прогін(арг[0], вихід=оп("--вихід"), макс=int(оп("--макс", 5000)),
           режим_мови=оп("--мова", "строго"))
    return 0


def записати(шлях, звіт, offers, кат):
    корінь = ET.Element("yml_catalog", date=str(datetime.datetime.now())[:16])
    shop = ET.SubElement(корінь, "shop")
    ET.SubElement(shop, "name").text = звіт["домен"] or звіт["файл"]
    cs = ET.SubElement(shop, "categories")
    вжиті = {o["cid"] for o in offers if o["cid"]}
    for cid in sorted(вжиті, key=lambda x: str(x)):
        якщо = кат.get(cid)
        e = ET.SubElement(cs, "category", id=str(cid))
        if якщо and якщо[1]:
            e.set("parentId", str(якщо[1]))
        e.text = (якщо[0] if якщо else "")
    os_ = ET.SubElement(shop, "offers")
    for o in offers:
        атр = dict(id=str(o["id"] or ""))
        if o["group_id"]:
            атр["group_id"] = str(o["group_id"])
        if o["available"] is not None:
            атр["available"] = str(o["available"])
        e = ET.SubElement(os_, "offer", **атр)
        for т, v in o["поля"].items():
            ET.SubElement(e, т).text = str(v)
        for ф in o["фото"]:
            ET.SubElement(e, "picture").text = ф
        for імя, v in o["парам"]:
            ET.SubElement(e, "param", name=імя).text = v
        ET.SubElement(e, "param", name="джерело").text = звіт["файл"]
        ET.SubElement(e, "param", name="знято").text = str(datetime.date.today())
    ET.ElementTree(корінь).write(шлях, encoding="utf-8", xml_declaration=True)


if __name__ == "__main__":
    raise SystemExit(main())
