def код_дрес(дрес_код, подія=None):
    """Рядок дрес-коду → ключ КОДИ_ДІАПАЗОНИ (або None).

    ДВА ВХОДИ, ЯК ВИМАГАЄ ТЕМА-5 §1.2: сам рядок і ТИП ПОДІЇ. Без другого частина
    рядків не має однозначного рівня — і це властивість джерела, не наша.
    Третій вихід (неоднозначність) віддає `неоднозначність_коду`, бо тут потрібен
    ключ, а не пояснення; змішувати їх в одному значенні означало б змусити
    кожного викликача розбирати кортеж.
    """
    if not дрес_код: return None
    к = str(дрес_код).lower().replace("-", "_").replace(" ", "_")
    return к if к in КОДИ_ДІАПАЗОНИ else None


def неоднозначність_коду(дрес_код, подія=None):
    """(чому) — коли рядок коду не має одного рівня; None, коли має.

    Подія знімає неоднозначність там, де джерело її знімає: весільний контекст
    відсилає до весільної матриці, побутовий — до гіда вбрання. Коли події нема,
    неоднозначність НЕСЕТЬСЯ ДАЛІ, а не гаситься дефолтом.
    """
    if not дрес_код: return None
    к = str(дрес_код).lower().replace("-", "_").replace(" ", "_")
    чому = КОДИ_НЕОДНОЗНАЧНІ.get(к)
    if not чому: return None
    п = str(подія or "").lower()
    if any(w in п for w in ВЕСІЛЬНІ_НАГОДИ):
        return ("«%s» прочитано за ВЕСІЛЬНОЮ таксономією (подія весільна). %s" % (к, чому))
    if п:
        return None            # подія названа й не весільна — читаємо гід вбрання
    return ("«%s» не має одного рівня без типу події: %s. Смуга взята за гідом "
            "вбрання; тип події зняв би неоднозначність" % (к, чому))


def формальність_образу(E, сцен=None, вечір=False, тіло=None):
    """K-KOH-02 / K-KOH-05+09 / K-KOH-10 — рівень образу проти сценарію.
    Формальність береться з поля речі (або з лексикона типу як фолбек); речі без неї
    просто не беруть участі — правило НЕ вигадує рівень.

    K-KOH-02 (C·strong): розкид формальності в образі ≤2 кроки; взуття жорсткіше
      (K-SHO-03) — тому відхилення взуття важить більше.
    K-KOH-03: high-low — один свідомий розрив, заякорений повтором/фокусом, законний;
      тому знахідка слабшає, коли розрив РІВНО один.
    K-KOH-05+09: образ має влучати в діапазон сценарію; напрям промаху читається через
      risk_posture (з господарем краще трохи вище, у креативному — трохи нижче).
    K-KOH-10: у денних/ділових контекстах відкрита максимум одна зона, у вечірніх — дві."""
