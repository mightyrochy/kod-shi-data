# ── ВІДКРИТІ ЗОНИ: ВИВОДЯТЬСЯ, А НЕ ЧЕКАЮТЬСЯ ──────────────────────────────
# ДІРА, ЗНАЙДЕНА ПЕРЕВІРКОЮ КОДУ: поле `відкрита_зона` ЧИТАЮТЬ три правила
# (K-KOH-10, K-PC-08 вето, `покриття_без_поля`), а ПИШЕ його НІХТО. У всій кодовій базі
# воно трапляється один раз — у фікстурі тесту. Тобто K-PC-08 (hard!) на реальному
# каталозі мовчав би завжди, а K-KOH-10 не спрацював би ніколи. Це той самий клас
# сироти, що й `тип` до правки: правило не хибне, а БЕЗ ВХОДУ.
#
# ДРУГИЙ ДЕФЕКТ, У ТОМУ Ж МІСЦІ Й ГЛИБШИЙ: поле СКАЛЯРНЕ («одна зона на річ»), а
# правило рахує `len(зони)` по РЕЧАХ. Коментар вище пояснює чому: колись рахувалось по
# записах кольорів і сукня в трьох кольорах давала «декольте, декольте, декольте».
# Полагодили переліком речей — і перекрутили в інший бік: сукня без рукавів із
# глибоким вирізом і довжиною міні відкриває ТРИ зони й рахується як ОДНА.
# При денному ліміті 1 такий образ проходить.
# Правильна одиниця — не запис і не річ, а ЗОНА ТІЛА: множина по речах, потім її
# потужність.
#
# ЩО ЦЕ МІНЯЄ В РІШЕННІ: раніше K-KOH-10 бачив 1 зону в такій сукні й мовчав; тепер
# бачить 3 при ліміті 1 і говорить. K-PC-08 отримує вхід і починає працювати на
# каталозі, а не лише на фікстурі.
_БЕЗ_РУКАВІВ = ("без рукав", "безрукав", "майка", "топ", "бралет", "корсет",
                "сарафан", "sleeveless", "tank",
                # 27.08.2026: слово param «рукав» жниварки (без рукава 105, бретелі 29)
                "бретел")
_СПИНА = ("відкрита спина", "відкритою спиною", "open back", "виріз на спині",
          "спина гол")
_ЖИВІТ = ("кроп", "crop", "укорочен", "топ-кроп", "бандо")
_ПЛЕЧІ_ВІДКР = ("відкриті плечі", "off-shoulder", "спущені плечі", "бардо")

def зони_речі(r, тіло=None, коліно_см=None):
    """Множина зон тіла, які ця річ відкриває. Виводиться з полів, що вже є:
    `виріз`, `тип`, `назва`/`id`, і геометрії краю проти рівня коліна.

    Повертає (зони, чому) — де `чому` несе, ЯК кожна зона виведена, бо частина
    висновків груба (поле `виріз` двійкове) і це має бути видно.

    ⚠ ЩО ЦЕ НЕ ЛОВИТЬ: рукав 3/4 проти довгого; глибину вирізу в сантиметрах;
    прозорість тканини (сітка відкриває зону, не будучи «відкритою» за кроєм);
    розріз на спідниці. Усе це вимагає полів, яких у фіді нема. Частка речей, де
    зони виведені НЕПОВНО, лишається невідомою, доки не буде реального фіду."""
    текст = " ".join(str(r.get(k) or "") for k in ("назва", "id", "річ", "тип",
                                                   "крій", "підтип", "рукав_слово")).lower()
    зони, чому = set(), []
    if r.get("виріз") == "відкритий":
        зони.add("декольте"); чому.append("виріз «відкритий» → декольте")
    if any(k in текст for k in _БЕЗ_РУКАВІВ):
        зони.add("руки"); чому.append("тип/назва вказує на відсутність рукава → руки")
    if any(k in текст for k in _ПЛЕЧІ_ВІДКР):
        зони.add("плечі"); чому.append("назва вказує на відкриті плечі")
    if any(k in текст for k in _СПИНА):
        зони.add("спина"); чому.append("назва вказує на відкриту спину")
    if any(k in текст for k in _ЖИВІТ):
        зони.add("живіт"); чому.append("кроп/укорочений крій → живіт")
    # НОГИ: край вище коліна. Рівень коліна береться З ТІЛА, не з константи —
    # «вище коліна» на зрості 152 і 178 це різні сантиметри.
    к = коліно_см
    if к is None and тіло:
        к = next((y for nm, y, _ in (тіло.get("профіль") or []) if nm == "коліно"), None)
    низ = r.get("низ_см")
    if к is not None and низ is not None and r.get("слот") in ("низ", "сукня", "комплект"):
        if float(низ) > float(к):
            зони.add("ноги")
            чому.append("поділ на %.0f см вище коліна (%.0f см) → ноги"
                        % (float(низ), float(к)))
    if r.get("відкрита_зона"):          # явно заявлене поле не втрачається
        зони.add(str(r["відкрита_зона"]).strip().lower())
        чому.append("заявлено полем `відкрита_зона`")
    return зони, чому


def відкриті_зони_образу(E, тіло=None):
    """(множина зон, за_речами, без_підстав). Одиниця — ЗОНА ТІЛА, не річ і не запис."""
    усі, за_річчю, без = set(), {}, []
    for e in одна_на_річ(E):
        з, чому = зони_речі(e, тіло=тіло)
        if з:
            усі |= з
            за_річчю[e.get("річ") or e.get("id")] = dict(зони=sorted(з), чому=чому)
        else:
            без.append(e.get("річ") or e.get("id"))
    return усі, за_річчю, без


