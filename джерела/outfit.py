# ЧОМУ ЦЕ НЕ ДУБЛЮЄ K-KOH-02: та міряє розкид формальності МІЖ РЕЧАМИ образу. Ця —
# розлад УСЕРЕДИНІ ОДНІЄЇ РЕЧІ: твідовий смокінг, атласні спортивні штани. Розкид між
