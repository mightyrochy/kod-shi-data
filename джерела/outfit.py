def перевірка_сегментації(F, E, tol=3.0):
    """Найнебезпечніший провал ланцюжка — САМОПІДТВЕРДНИЙ.
    Маска волосся, що зачепила темний верх (класика face-parsing: чорне волосся
    на чорному гольфі), дає «волосся» кольору гольфа. Контраст особи рахується
    саме з волосся -> особа хибно стає висококонтрастною -> K-CLR-02 пропускає
    той самий гольф, який і зіпсував вимір. Помилка сама себе схвалює, і жодне
    правило кольору її не бачить, бо всі числа узгоджені між собою.
    Тому: якщо риса особи нерозрізнима з річчю біля обличчя — стоп, а не вердикт."""
    out = []
    ризик = {k: v for k, v in F.items()
             if k.startswith("волосся") or k in ("очі", "оправа")}
    for k, f in ризик.items():
        lab = (f["L"], f.get("a", 0), f.get("b", 0))
        for e in E:
            if e["near"] < 0.5: continue
            d = de00(lab, e["lab"])
            if d < tol:
                out.append(dict(правило="сегментація", сила="утримано",
                    сила_нп=None, сила_нп_джерело="виміру нема (утримано): маски ненадійні",
                    суть=f"«{k}» і «{e['річ']}» нерозрізнимі (ΔE00={d:.1f})",
                    речі=[k, e["річ"]],
                    чому="або маска риси зачепила річ, або вони справді одного кольору — "
                         "з самих чисел це не розрізнити",
                    ризик="якщо зачепила: контраст особи завищено, і K-CLR-02 схвалить "
                          "саме ту річ, що зіпсувала вимір — помилка підтвердить себе",
                    ремонт="перевірити маску риси на перекриття з річчю; за сумніву — "
                           "фото особи без цієї речі біля обличчя"))
    return out


