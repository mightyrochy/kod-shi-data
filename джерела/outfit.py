# проти числової смуги, сила `soft`. Заборони на тип не існують.»
#
# Медіана — не переклад цих вимог, а їх заміна найближчим скаляром. Різниця
# видима на речі: спортивний костюм із дорогої тканини має високу формальність
# полярностями й проходить медіану на `cocktail`, хоч корпус його там забороняє
