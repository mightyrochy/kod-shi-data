                # 24.08.2026: множник ×0.6 — це і є правило «один свідомий розрив
                # законний», але ID жив лише в тексті ремонту, тож у сліді
                # послаблення не приписувалось нікому. Чесна межа реалізації:
                # з трьох умов корпусу перевіряється лише ОДИНИЧНІСТЬ розриву;
                # якір (повтор/фокус) і бездоганність посадки модуль не бачить —
