# ЧОМУ ЦЕ ДОПИСАНО (07.09.2026). Звірка механізмів назвала K-KOH-05 ПІДМІНОЮ:
# «корпус (`hard` там, де код названо) перелічує вимоги до ТИПІВ речей на кожен
# дрес-код (сукня в підлогу; без деніму; без спортивних; кроєний низ АБО
