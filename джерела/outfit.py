    # Розкид міряється між КРАЯМИ, що дивляться один на одного: якщо інтервали
    # перекриваються, спільний рівень існує і розкид нульовий. Саме це знімає high-low
    # без окремого винятку — блуза (4..7) і джинси (2..4) перекриваються на 4.
    _і = [(e, інтервал_формальності(e)) for e in одна_на_річ(E)]
    _і = [(e, lo, hi) for e, (lo, hi) in _і if lo is not None]
    рівні = [(e, (lo + hi) / 2.0) for e, lo, hi in _і]     # середина — для тексту
    зн = []
    if len(_і) >= 2:
        значення = [v for _, v in рівні]
        верх_і = max(_і, key=lambda x: x[1])               # найвищий НИЖНІЙ край
        низ_і = min(_і, key=lambda x: x[2])                # найнижчий ВЕРХНІЙ край
        розкид = max(0.0, верх_і[1] - низ_і[2])            # зазор між інтервалами
        # §15.1: допуск залежить від контексту, а не глобальний
        престиж = престижний_контекст(сцен, вечір)
        допуск = ФОРМ_РОЗКИД_МАКС if престиж in (True, None) else ФОРМ_РОЗКИД_ЗВИЧАЙНЕ
        над = розкид - допуск
        if над > 0:
            низ = (низ_і[0], низ_і[2]); верх = (верх_і[0], верх_і[1])
            взуттєве = 1.25 if низ[0]["слот"] == "взуття" or верх[0]["слот"] == "взуття" else 1.0
            # K-KOH-03: рівно один випадаючий елемент — законний high-low, слабшає
