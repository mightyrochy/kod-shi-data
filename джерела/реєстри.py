    поля = ("назва", "тип", "тип_верхнього", "тканина", "матеріал", "крій",
            "візерунок", "принт", "деталі_крою", "колір_назва")
    куски = []
    for п in поля:
        v = р.get(п)
        if isinstance(v, (list, tuple)):
            куски += [str(x) for x in v]
        elif v:
            куски.append(str(v))
    return _норм(" ".join(куски).lower())


