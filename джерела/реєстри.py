_КІНЦІ = "а-яіїєґА-ЯІЇЄҐa-zA-Z0-9"
_КЕШ_РЕГ = {}


def _є(маркер, текст):
    """Чи стоїть маркер на ПОЧАТКУ слова в тексті. Кінець слова вільний: маркери
    навмисно подані основами («вовн», «блейзер»), щоб ловити відмінки."""
    r = _КЕШ_РЕГ.get(маркер)
    if r is None:
        r = _КЕШ_РЕГ[маркер] = re.compile(
            r"(?<![%s])%s" % (_КІНЦІ, re.escape(_норм(маркер))))
    return bool(r.search(текст))


