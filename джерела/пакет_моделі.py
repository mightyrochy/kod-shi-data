    # ЧОМУ ТУТ, А НЕ У ФІДІ. Фід лише КАЖЕ, що показати нема чого (поле
    # `без_показу`, дані виміру `фід_фото`); рішення «річ не йде в образ» живе
    # там, де вже живуть «ціни нема» й «не одяг для випадку», — щоб його було
