    # купити, продуктом не є.
    # ВИМІР на каталог_повний: 126 речей із 12 405 (1.0 %) несуть `<price>0</price>` —
    # 62 kasandra.ua (з 280), 55 vilni.store (з 253), 9 по дев'ятьох інших крамницях.
    # Це не «безкоштовно», а втрачене поле жнив: в obох крамницях ціна є на сайті.
