    # СЛОВО ВЛАСНИКА 24.09: «Прибрати skripka з образів рук», і ширше —
    # «Заглушки не потрібні: або витягуємо фото замість заглушок, або прибираємо
    # речі з каталогу». skripka — один випадок одного правила: річ, фото якої
    # браузер НЕ ПОКАЖЕ, в образі рук 1–2 бути не може. Рука 1 — це продукт, а
    # образ, у якому замість речі порожній квадрат чи арка, продуктом не є — та
