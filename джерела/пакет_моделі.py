# ── ПОЗНАЧКА ЖІНКИ «НЕ ЦЯ» — НАЗВАНЕ ВІДСІЧЕННЯ, А НЕ МОВЧАННЯ (рядок 149) ──
# Картка сама обіцяє жінці: «познач «не ця» на речі, і образ зберуть заново».
# Доти обіцянка була порожня: позначка жила рівно у відповіді вердикта
# (`показ.html: В[поз].замінити`) і їхала тільки в запис вердикту — пул її не
# бачив, і «Зібрати ще раз» повертало ту саму річ (виміряно куратором 23.09 на
# сумці ж-08232@attico.ua). Причина стоїть ОКРЕМИМ рядком лічби, а не всередині
# `_жорстке_відсічення`: там живе те, що НЕ ПІДХОДИТЬ випадку (температура,
# рівень події, вето слова), а тут — те, що жінка сказала про КОНКРЕТНУ річ.
# Злити їх означало б сховати її слово серед висновків коду.
ПРИЧИНА_НЕ_ЦЯ = "ти позначила «не ця»"


def відсікти_пул(кандидати, каталог, темп_c=None, вето=None, ошатність=None, не_ця=None, опади=None):
    """Пул після жорстких відсічень + звіт, що і чому знято. Комплект лишається ЛИШЕ у
    слоті «комплект» (половини беруться явним «/верх» «/низ»), а не дублем у верх/низ.

    `не_ця` — id речей, які жінка позначила «не ця» на картках ЦЬОГО сценарію
    (поле входу `не_ця`, `показ.html: НЕ_ЦЯ_П`). Вони знімаються ПЕРШИМИ й під
    власним іменем (`ПРИЧИНА_НЕ_ЦЯ`), тож у звіті `відсічено.лічба` видно саме її
    слово, а не «вето людини» чи «не одяг для випадку». Замка це не ставить:
    позначка знімається тим самим дотиком, і тоді id сюди не приїде.
    `опади` — слово нагоди; мокрі знімають замшу, нубук і велюр (K-WEA-01)."""
    за_ід = {r["id"]: r for r in (каталог or []) if r.get("id")}
    _не_ця = {str(x) for x in (не_ця or ()) if str(x or "").strip()}
    вих, звіт, приклади = {}, {}, {}
    for сл, пул in (кандидати or {}).items():
        нове = []
        for r in пул:
            к = за_ід.get(r.get("id"), r)
            if str(r.get("id") or "") in _не_ця:
                причина = ПРИЧИНА_НЕ_ЦЯ
            elif сл in ("верх", "низ") and (к.get("слот") == "комплект"):
                причина = "комплект лише у своєму слоті"
            else:
                rr = dict(к); rr.setdefault("слот", сл)
                причина = _жорстке_відсічення(rr, темп_c, вето, ошатність, опади)
            if причина:
                звіт[причина] = звіт.get(причина, 0) + 1
                приклади.setdefault(причина, (r.get("id"), str(к.get("назва") or "")[:50]))
                continue
            нове.append(r)
        вих[сл] = нове
    return вих, dict(лічба=звіт, приклади=приклади)


_СТОП = {"для", "або", "щоб", "які", "яка", "яке", "без", "під", "над", "при", "але", "теж", "дуже",
         "хочу", "хочеться", "треба", "потрібно", "бажано", "краще", "щось", "будь", "ласка"}

def _токени(т):
    """Слова фрази (≥ 3 знаків, у нижньому регістрі) без стоп-слів — список для пошуку словами."""
    return [w for w in re.findall(r"[a-zа-яіїєґ0-9]{3,}", str(т or "").lower()) if w not in _СТОП]

def шукати_словами(каталог, фраза, n=5, темп_c=None, вето=None):
    """Пошук речі по ВСЬОМУ каталогу словами (бажання людини або «потрібно» моделі) —
    під жорсткими відсіченнями, БЕЗ палітри. Збіг — за основами слів (перші 5 літер)."""
    т = _токени(фраза)
    if not т:
        return []
    основи = [w[:5] for w in т]
    оцінені = []
    for r in (каталог or []):
        if _жорстке_відсічення(r, темп_c, вето):
            continue
        текст = " ".join(str(r.get(k) or "") for k in ("назва", "тип", "тканина", "візерунок", "колір_назва", "крій")).lower()
        бал = sum(1 for о in основи if о in текст)
        if бал:
            оцінені.append((бал, r))
    оцінені.sort(key=lambda x: (-x[0], str(x[1].get("id"))))
    return [r for б, r in оцінені[:n]]
