    # рештою. Причина їде ТА САМА, що в даних (їх дві: крамниця заборонила
    # чужий показ / не відкрився жоден кадр), тож у звіті власника видно не
    # «знято N», а що саме сталось у кожної крамниці.
    # ЖІНЦІ ЦЬОГО РЯДКА НЕ ПОКАЗУЮТЬ: він іде у звіт вердиктів тим самим шляхом,
    # що й решта відсічень, — на картці речі просто нема.
    # ВИМІРЯНО на каталог_повний (24.09.2026): 400 речей з 11 993 (3,3 %) —
    # 353 skripka.com.ua (заборона `CORP: same-origin` на всі її знімки) і 47 по
