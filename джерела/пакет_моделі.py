    # РІВЕНЬ ПОДІЇ — ПО ВСІХ СЛОТАХ, НЕ ЛИШЕ ВЗУТТЯ (05.09, аудит слотів: в офіс formal ішли
    # 17 футболок, джинси, спортивні костюми, кепка; тип-інтервал їх пропускав)
