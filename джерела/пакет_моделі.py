def скелет_схеми(вузол):
    """Форма відповіді — з ТОГО САМОГО оголошення, яким її потім перевіряють.

    ЧОМУ НЕ ЗРАЗОК, ПИСАНИЙ РУКАМИ. Доти форму диктував рядок у
    `_формат_відповіді`: другий опис того, що вже оголошено у валідаторі. Вони й
    розійшлися — там `"свідомо": ["<річ> — <чому>", …]` (список РЯДКІВ), а в
    `протокол.ОБРАЗ_МОДЕЛІ` це список ОБ'ЄКТІВ `{річ, чому}`. Тобто код просив
    одне, перевіряв інше, і винною виглядала модель. Скелет рахується зі схеми,
    тож розійтися нема з чим: зміниться схема — зміниться і те, що ми просимо.
    РОЗБІР ЗА СТРУКТУРОЮ ВУЗЛА, А НЕ ЗА СЛОВОМ ТИПУ: ключі `поля`/`по_ключу`/
    `елемент` однозначні, а назви типів (`обʼєкт` з U+02BC) — рівно те місце, де
    копія в другому модулі розходиться на один невидимий символ.
    """
    в = вузол or {}
    if "поля" in в:
        return {к: скелет_схеми(з) for к, з in (в.get("поля") or {}).items()}
    if "по_ключу" in в:
        return {"<ключ>": скелет_схеми(в.get("по_ключу"))}
    if "елемент" in в:
        return [скелет_схеми(в.get("елемент"))]
    if в.get("значення"):
        return "|".join(str(x) for x in в["значення"])
    return "<%s>" % (в.get("тип") or "будь_що")


def _нейтральний_тон(h, C, L=None):
    """Нейтраль за корпусом (K-COL-06) — ОДНЕ означення на всю систему.

    ВІДДАНО `колір_образу.нейтраль` (17.09.2026). Тут стояла ВЛАСНА копія коридорів
    («те саме означення, що в рядках вікон»), і вона розійшлась із тим, на що
    посилалась: `колір_образу.нейтраль` піднімає стелю хроми холодної нейтралі до
    34 для темних (L ≤ 45, зона нейві), а копія тримала 24 на будь-якій світлоті.
    Наслідок вимірюваний: темно-синя річ була нейтраллю для `feed.підходить`
    (рядок вікна пускав її як нейтраль) і КОЛЬОРОМ для `схема_образу` — тобто той
    самий образ давав гейт K-PAL-03 на речі, яку пул узяв рівно як законну під
    будь-яку схему нейтраль. Два означення нейтралі в одній системі — це не два
    пороги, а два різні вердикти на одній речі.
    `L` необов'язкова лише заради старих викликів із парою (h, C): без неї темна
    гілка нейві недосяжна, і це сказано тут, а не приховано дефолтом.
    """
    if C is None:
        return True
    import math as _м, колір_образу as _КО
    if L is None:
        L = 50.0                               # світлота не названа — середина шкали
    r = _м.radians(float(h or 0.0))
    lab = (float(L), float(C) * _м.cos(r), float(C) * _м.sin(r))
    return _КО.нейтраль(lab) is not None


def _сім_я_кута(h):
    """Назва сім'ї за кутом тону (`palettes.СІМ_Ї`); None — кут у жодній дузі.

    ВИНЕСЕНО З `_сім_я_тону` (17.09.2026): те саме питання ставить K-PAL-07
    («скільки кольорових сімей у великих слотах»), і там колір уже розкладений на
    осі — ганяти його назад у hex заради того самого циклу було б другим тілом
    одного правила. `СІМ_Ї` перекриваються навмисно (див. коментар над словником),
    і нічию тут бере перша оголошена — те саме, що робить `перекриття_сімей`
    правилом «порядок».
    """
    if h is None:
        return None
    import palettes as _ПЛ
    for ім, версії in _ПЛ.СІМ_Ї.items():
        for д in (версії.get("тепла"), версії.get("холодна")):
            if not д:
                continue
            lo, hi = д
            if (lo <= hi and lo <= h <= hi) or (lo > hi and (h >= lo or h <= hi)):
                return ім
    return None


def _сім_я_тону(hex_):
    """Назва сім'ї тону за `palettes.СІМ_Ї` для hex речі; None — нейтраль або не виміряно."""
    if not hex_:
        return None
    try:
        import colorspace as _КС
        L, C, h = _КС.lch(_КС.hx(hex_))
    except (TypeError, ValueError, AttributeError):
        return None
    if C is None or C < 10:
        return None
    return _сім_я_кута(h)


def _у_дузі_вікон(hex_, слот, вікна):
    """True/False — чи лежить тон речі в дузі котрогось кольорового вікна її слота
    (або річ нейтральна); None — колір не виміряно або слот без дуг."""
    if not hex_:
        return None
    рядки = [q for q in (вікна or []) if isinstance(q, dict) and q.get("слот") == слот]
    дуги = [(q["h_from"], q["h_to"]) for q in рядки if q.get("h_from") is not None and q.get("h_to") is not None and not q.get("нейтраль")]
    if not дуги:
        return None
    try:
        import colorspace as _КС
        L, C, h = _КС.lch(_КС.hx(hex_))
    except (TypeError, ValueError, AttributeError):
        return None
    if _нейтральний_тон(h, C, L):
        return True
    for lo, hi in дуги:
        lo, hi = float(lo), float(hi)
        if (lo <= hi and lo - 8 <= h <= hi + 8) or (lo > hi and (h >= lo - 8 or h <= hi + 8)):
            return True
    return False


def _річ_пулу(r, ном):
    """Річ пулу об'єктом: групові ознаки стають ПОЛЯМИ речі (Т-02, крок 1).

    ПОРОЖНЄ ПОЛЕ НЕ ПИШЕТЬСЯ. `null` у кожній речі коштував би більше, ніж несе:
    «поля нема» і «поле порожнє» тут одне й те саме твердження — фід значення не
    знає. Схема (`протокол.РІЧ_ПУЛУ`) вимагає лише `н` і `назва`, решту оголошує
    необов'язковою рівно з цієї причини.
    НОМЕР — КЛЮЧ `н`, і він той самий, що бачить `ід_з_тексту`: нумерація
    роздається по ПОВНОМУ пулу (`номери_речей`), тож підмножина, пронумерована
    сама по собі, резолвилась би в іншу річ іншого магазину.
    КОЛЬОРУ ТУТ НЕМА НАВМИСНО: рядок кандидата не несе слова про колір і доти —
    його тримає фільтр палітри, крізь який пул уже пройшов. Оголосити поле й
    заповнити його hex-ом означало б дати моделі нашу внутрішню шкалу; вигадати
    слово — назвати колір, якого код не міряв.
    """
    _н = ном.get(r.get("id")) if ном else None
    річ = {"н": ("#%d·%s" % _н) if _н else str(r.get("id") or ""),
           "назва": str(r.get("назва") or "")}
    for ключ, значення in (
            # Ціна 0 — це «магазин не сказав», а не «безкоштовно»: у прозі така
            # річ ішла без ціни, і поле тут так само не з'являється.
            ("ціна", r.get("ціна") or None),
            ("тип", (r.get("тип") or r.get("тип_верхнього") or "").replace("_без_уточнення", "")),
            ("крій", r.get("крій")),
            ("гілка", r.get("гілка") or "ядро"),
            ("тканина", r.get("тканина")),
            ("матеріал", МАТЕРІАЛ_СЛОВОМ.get(r.get("матеріал"), "")),
            ("довжина", ДОВЖИНА_СЛОВОМ.get(r.get("довжина"))),
            ("рукав", r.get("рукав")),
            ("каблук", r.get("каблук")),
            ("халява", ХАЛЯВА_СЛОВОМ.get(r.get("халява"), r.get("халява"))),
            # «solid» — службове слово фіду для «без візерунка», не ознака речі.
            ("візерунок", (r.get("візерунок") if r.get("візерунок") != "solid" else None)),
            # Блиск фід міряє балом; моделі потрібен факт, а не наш бал (та сама
            # межа, що й у шапці групи: поріг 2).
            ("блиск", True if (r.get("блиск") or 0) >= 2 else None),
            ("зона", r.get("зона")),
            ("колір", r.get("колір")),
            ("hex", r.get("hex")),
            ("сім_я", r.get("сім_я")),
            ("реєстр", r.get("реєстр")),
            ("схема", r.get("схема")),
            ("деталі", _деталі_речі(r)),
            ("може_стати", list(r.get("слоти_альт") or ())),
            ("є_також_у", [x for x in (r.get("також_у") or []) if x and x != "інший колір"][:3]),
    ):
        if значення not in (None, "", [], ()):
            річ[ключ] = значення
    if r.get("у_дузі") is not None:          # False — теж факт: річ поза дугою схеми
        річ["у_дузі"] = bool(r.get("у_дузі"))
    # РЯДОК 159: чиє бажання ця річ виконує і чи стояла вона вже в її образах цього
    # сценарію — фактами речі, щоб рядок вимоги пакета мав на що вказати.
    if r.get("за_бажанням"):
        річ["за_бажанням"] = str(r["за_бажанням"])
    if r.get("вже_був"):
        річ["вже_був"] = True
    return річ


def випадок_для_пакета(паспорт, рядок, сценарій=None, вимоги=""):
    """ВИПАДОК пакета: паспорт як він є плюс `рядок` — той самий текст, що в рук 3–4.

    ПОЛЕ, ЯКОГО НЕМА, НЕ ВИГАДУЄТЬСЯ (п. 11 СТАНДАРТУ_КОДУ). Схема
    `протокол.ВИПАДОК` вимагає лише `подія` і `рядок`; решта або має в переліку
    слово «невідомо», або чесний `null` у самому паспорті. Тому тут не дефолти, а
    ПЕРЕНОС: що паспорт знає — те й їде, і жодне слово не домальовується.
    ПЕРЕЛІК БЕРЕТЬСЯ З СХЕМИ, А НЕ ПОВТОРЮЄТЬСЯ ТУТ: значення поза enum-ом краще
    не передати зовсім, ніж підмінити сусіднім словом. Так `fashion_forward`
    (намір, якого ВИПАДОК не знає — там лише `conventional|statement`) не їде
    зовсім: намір модель і так бачить мітками гілок у пулі й дозволеним розривом.
    БЕЗ ПАСПОРТА (CLI, стенд, руки без виклику 0) `подія` збирається з нагоди й
    місця сценарію: інакше на входах без паспорта валідний пакет не склався б
    узагалі, і протокол відмовляв би половині живих шляхів.
    ВИМОГИ ЛЮДИНИ СТОЯТЬ У ВИПАДКУ, А НЕ В `завдання.вимоги`: «це частина
    випадку, а не правило коду» (`brief._вимоги`) — і старшинство над умовами
    коду в них саме тому, що вони її.
    """
    поля = _ПР.ВИПАДОК["поля"]
    в = {}
    for к, v in (паспорт or {}).items():
        if к not in поля or v in (None, "", [], {}):
            continue
        дозволені = поля[к].get("значення")
        if дозволені and v not in дозволені:
            continue
        в[к] = v
    сц = сценарій or {}
    if not str(в.get("подія") or "").strip():
        в["подія"] = ", ".join(str(сц.get(к) or "").replace("_", " ").strip()
                               for к in ("нагода", "місце")
                               if str(сц.get(к) or "").strip()) or str(рядок or "")
    в["рядок"] = str(рядок or в["подія"])
    if str(вимоги or "").strip():
        в["вимоги_людини"] = str(вимоги).strip()
    return в


def людина_для_пакета(тіло, палітри, гілка=None, спец=None, вибір=None):
    """ЛЮДИНА пакета: контраст, температура, палітра, тіло (`протокол.ЛЮДИНА`).

    РИС ТУТ НЕ ЧИТАЄМО НАПРЯМУ, І `F` ПЕРШИМ ПАРАМЕТРОМ ЗНЯТО: усе, що пакет має
    сказати про людину кольором, уже пораховане в `палітри` (контраст, температура,
    практична палітра) і в `спец`. Другий шлях до тих самих рис давав би дві відповіді
    на одне питання — рівно те, проти чого §4 п.12.

    СВІТЛОТИ ТУТ НЕМА, І ЦЕ РІШЕННЯ, А НЕ ПРОПУСК. Схема не вимагає її з тієї ж
    причини, з якої не вимагає контрасту: у світлоти рис нема СЛОВА для «входу
    нема», а поставити «середня» без виміру — маскувальний дефолт. Числа L* сюди
    теж не йдуть: це наша внутрішня шкала, і промпт від самого початку забороняє
    моделі нею говорити («не називай чисел світлоти»). Контраст, натомість, слово
    має (`палітри.контраст_рівень`) — тому він і є.
    ДЖЕРЕЛО ТЕМПЕРАТУРИ ЗВОДИТЬСЯ ДО ОДНОГО З ТРЬОХ СЛІВ, бо `palette.температура`
    віддає його цілим реченням («елісітація (золото, впевненість 0.80) — не
    залежить від камери»), а речення в полі, за яким модель приймає рішення, —
    це прози в даних. Правило переносу: була елісітація → `самозвіт`; клас
    придатний із фото → `фото`; класу нема → `утримано` і `не_стверджується`.
    АКЦЕНТИ — ЦЕ НЕЙТРАЛЬНІ КОЛЬОРИ ПАЛІТРИ НАВИВОРІТ. `палітра_практична`
    називає роль кожного кольору «нейтраль» або «колір»; хто з них буде акцентом
    у ЦЬОМУ образі, вирішує `ролі_слотів` (домінанта/секундант/акцент по слотах).
    Тому `нейтралі` — нейтралі, а `акценти` — решта палітри, тобто матеріал для
    акценту, а не призначений акцент.
    """
    л = {}
    рівень = (палітри or {}).get("контраст_рівень")
    if рівень in (_ПР.ЛЮДИНА["поля"]["контраст"].get("значення") or ()):
        л["контраст"] = рівень
    т = (палітри or {}).get("температура") or {}
    _кл = т.get("клас") if т.get("придатно") else None
    л["температура"] = {
        "клас": _кл if _кл in _ПР.ТЕМПЕРАТУРА_КЛАСИ else "не_стверджується",
        "джерело": ("самозвіт" if (т.get("елісітація") or {}).get("w") is not None
                    else "фото" if _кл else "утримано"),
    }
    розвилка = (палітри or {}).get("розвилка") or []
    _г = (розвилка[гілка] if (гілка is not None and -len(розвилка) <= гілка < len(розвилка))
          else None)
    сп = спец if isinstance(спец, dict) else ((_г or {}).get("спец") or {})
    пал = {"схема": str(сп.get("схема") or (_г or {}).get("схема") or "")}
    ролі = {с: (v or {}).get("роль") for с, v in (сп.get("слоти") or {}).items()
            if isinstance(v, dict) and v.get("роль")}
    if ролі:
        пал["ролі_слотів"] = ролі
    _кольори = ((сп.get("палітра_практична") or {}).get("кольори") or [])
    def _слова(ролі_кольору):
        """Кольори практикової палітри названих ролей рядками «назва hex», без повторів.

        Порядок лишається той, що в `палітра_практична.кольори`: він уже є
        рішенням палітри (роль за роллю), і пересортувати його тут означало б
        завести другий порядок поруч із першим."""
        вих = []
        for к in _кольори:
            if (к.get("роль") or "") not in ролі_кольору:
                continue
            с = " ".join(x for x in (к.get("назва"), к.get("hex")) if x)
            if с and с not in вих:
                вих.append(с)
        return вих
    _н = _слова(("нейтраль", "світла_нейтраль", "темна_нейтраль"))
    _а = _слова(("колір",))
    if _н: пал["нейтралі"] = _н
    if _а: пал["акценти"] = _а
    # ── ЩО ЖІНЦІ ТРЕБА ЗНАТИ ПРО СВОЮ ПАЛІТРУ, КРІМ СПИСКУ КОЛЬОРІВ ──────────
    # K-PAL-11 (метал), K-PAL-14 (найдальші), K-PAL-15 (поєднання) і прийоми
    # K-PAL-02…13 рахувались і лишались у `palettes.словами`, тобто в брифі ДЛЯ
    # ЛЮДИНИ, — а в пакет, за яким модель складає образ, не їхали. Стиліст видає
    # не список кольорів, а метал, «чого уникати» і пару готових поєднань
    # (тема-2:1861, 1865); модель їх не бачила й видати не могла.
    # Числа не їдуть: склад називає `palettes.для_пакета`, і там сказано чому.
    # П.14 (СТАНДАРТ §4): мовчазний `except` тут повертав би рівно ту ваду, яку
    # цей абзац і лагодив, — метал, «чого уникати» і поєднання не доїжджають до
    # моделі, і в пакеті це виглядає як «палітра їх не порахувала».
    # `для_пакета` бере порожній dict без нарікань, тож «палітри ще нема» —
    # не виняток, а звичайний вхід.
    import palettes as _ПЛ
    пал.update(_ПЛ.для_пакета((сп.get("палітра_практична") or {})))
    # КОЛІР, ЯКИЙ ОБРАЛА ЛЮДИНА, СТОЇТЬ У ПАЛІТРІ, А НЕ В ІНСТРУКЦІЇ. Реченням
    # («ОСНОВНИЙ КОЛІР ОБРАЗУ: … вона обрала сама») воно їде в руки 3–4, де іншого
    # каналу нема; тут канал є, і «за замовчуванням ≠ вибір» лишається видимим
    # полем `джерело`, а не прикметником у прозі.
    база = (вибір or {}).get("база")
    if база:
        пал["основа"] = {к: v for к, v in (
            ("слово", str(база).split("·")[0]),
            ("hex", (вибір or {}).get("база_hex")),
            ("джерело", ("код запропонував, вона не міняла"
                         if (вибір or {}).get("база_за_замовчуванням") else "вона обрала сама")),
        ) if v}
    л["палітра"] = пал
    тл = {}
    try:
        _зріст = float((тіло or {}).get("зріст"))
    except (TypeError, ValueError):
        _зріст = None
    if _зріст:
        тл["зріст"] = round(_зріст, 1)
    # ОБХВАТІВ МЕНШЕ, НІЖ ТРЕБА ДЛЯ ЯРЛИКА, — ЦЕ СТАН ВХОДУ, І ВІН ПИТАЄТЬСЯ
    # УМОВОЮ, А НЕ ВИНЯТКОМ (п.14, СТАНДАРТ §4). `fit.зони` читає рівно чотири
    # обхвати; без будь-якого з них він кидав KeyError, а `except Exception …
    # pass` рівняв цей нормальний стан із будь-якою поломкою посадки. `ярлик` у
    # `протокол.ЛЮДИНА` не в `треба` саме тому, що його законно може не бути;
    # тепер його відсутність означає рівно одне — обхватів нема.
    _обх = (тіло or {}).get("обхвати") or {}
    if all(_обх.get(_к) for _к in ("плечі", "груди", "талія", "стегна")):
        import fit as _ПС
        _з = _ПС.зони(тіло)
        тл["ярлик"] = _з.get("ярлик")
        тл["зони"] = _з.get("вектор") or {}
    л["тіло"] = тл
    return л


# ── РЯДКИ КАНДИДАТІВ БУДУЮТЬСЯ РАЗ НА ПУЛ, А НЕ РАЗ НА ІТЕРАЦІЮ (17.09.2026) ──
# `bridge._пакет_у_бюджет` шукає зріз під бюджет БІНАРНИМ ПОШУКОМ і кличе
# `пакет_для_моделі` ~12 разів на руку з ТИМ САМИМ `рез`, тими самими вікнами й
# тим самим тілом: міняється лише `семплер`, а він працює ВЖЕ НАД зібраними
# рядками. Тобто 23 рази поспіль будувався той самий 1 790-рядковий пул:
# `_у_дузі_вікон` 41 290 викликів (6.0 с профільної шкали), `_РЕ_кандидата`
# 41 290 (3.9 с), `composer._у_річ` 41 290 (1.8 с) — при 3 580 потрібних. Це і був
# «квадрат» бюджетного циклу: ціна ітерації росла з розміром пулу, хоч ітерація
# міняла тільки число зрізу.
# КЛЮЧ — ТОТОЖНІСТЬ, А НЕ РІВНІСТЬ (`is`), і кеш ТРИМАЄ ці об'єкти посиланням:
# порівнювати 1 790 словників дорожче, ніж їх побудувати, а `id()` без утримання
# посилання інтерпретатор перевикористовує — і кеш віддав би рядки ЧУЖОГО пулу.
# `рез=None` (композитор збирає новий об'єкт щоразу) у кеш не влучає НІКОЛИ, і це
# правильно: тоді пул справді інший.
# СЛОТ ОДИН: живий шлях іде рукою B до кінця, тоді рукою C, і другий слот тримав
# би зайвий пул у пам'яті телефона ні для кого.
_КЕШ_РЯДКІВ = {}


def _рядки_кандидатів(тіло, вікна, K, рез):
    """{слот: [рядок кандидата]} — те, що поїде моделі, ДО зрізу семплером.

    ПУЛ ПРИХОДИТЬ ЗІБРАНИМ (`рез["_кандидати"]`), тому `F`, `каталог` і `слоти` тут
    не потрібні й знято: фільтрація по людині й каталогу вже відбулась у `composer`,
    а перелік слотів цього прогону читається з самого пулу (`_живі_слоти` нижче).

    Віддає КОПІЇ рядків: далі їх переставляє семплер і читає `_річ_пулу`, а
    майстер-копія кеша мусить лишитись тією, якою її склали.
    """
    # ЛІЧБА В КЛЮЧІ — СТОРОЖ ПРОТИ ДОПИСУВАННЯ В ПУЛ. `_пакет_у_бюджет` міняє
    # `рез["_кандидати"]` (відсічення, бажання людини, добір обов'язкового слота)
    # ДО першого пакета, але тотожність `рез` при цьому не змінюється — а кеш за
    # самою лише тотожністю віддав би рядки пулу, якого вже нема.
    _лічба = tuple((с, len(v)) for с, v in (рез.get("_кандидати") or {}).items())
    _кеш = _КЕШ_РЯДКІВ.get("ключ")
    if (_кеш is not None and _кеш[0] is рез and _кеш[1] is вікна
            and _кеш[2] is тіло and _кеш[3] == K and _кеш[4] == _лічба):
        return {с: [dict(r) for r in рч] for с, рч in _КЕШ_РЯДКІВ["рядки"].items()}
    import composer as _КМ, graph as _ГР, семплер as _СМ_
    кандидати = {}
    # СЛОТИ, ЯКІ В ЦЬОМУ ПРОГОНІ СПРАВДІ Є. Мітка двослотовості («може стати також:
    # верхній_шар») має сенс лише тоді, коли той слот у цьому образі існує. Без
    # фільтра рядок кандидата підказував шар при +26 °C, де слот законно відсутній
    # (composer знімає його за температурною мапою) — тобто код кликав би людину
    # вдягнути кардиган поверх у спеку.
    _живі_слоти = set(рез.get("_кандидати") or {})
    for с, пул in (рез.get("_кандидати") or {}).items():
        рядки = []
        # ── КАП РІЖЕ ПО ГІЛКАХ, А НЕ ПЛОСКИМ ЗРІЗОМ (30.08.2026) ──────────────
        # ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after, каталог_повний, сцена «вечеря ·
        # ресторан · cocktail · statement», сід 42):
        #   before — K=20 давав ші {ядро: 20} у КОЖНОМУ слоті. Гілки стоять у
        #            хвості (ядро + межа + розрив конкатенацією), тож `пул[:20]`
        #            зрізав рівно те, заради чого сміливий намір існує: 20 речей
        #            «на межі» у верху, 20 «на межі» + 20 «розрив» у низу — усе
        #            за борт. Під statement до моделі не доходила жодна річ поза
        #            ядром палітри, тобто намір знову не мав шляху до вибору.
        #   after  — `_підпул` бере перші K КОЖНОЇ гілки: верх 20+20, низ
        #            20+20+20, взуття 20+7, сумка 20.
        # Це той самий дефект і те саме лікування, яким `_підпул` уже стереже
        # перебір композитора; у виході до ші його не стеріг ніхто.
        for r in (_КМ._підпул(пул, K) if K else пул):
            рч = _КМ._у_річ(dict(r), с, тіло)
            рядки.append(dict(id=r.get("id"), назва=r.get("назва"), ціна=r.get("ціна"),
                              url=(r.get("параметри") or {}).get("джерело_url") or r.get("url"),
                              зона=_ГР.зона_словами(_ГР.зона(рч)),
                              частка_вікна=r.get("_частка_вікна"),
                              # КОЛІР РЕЧІ ЇДЕ ДО МОДЕЛІ (16.09.2026). Доти «кольору тут нема
                              # навмисно», і модель складала тональні образи з речей,
                              # кольорів яких не бачила. Слово — крамниці, hex — код виводить
                              # із виміру, сім'я і «у дузі» — його ж суд над цим же виміром.
                              колір=(r.get("колір_назва") or None),
                              hex=(рч.get("hex") or None),
                              сім_я=_сім_я_тону(рч.get("hex")),
                              у_дузі=_у_дузі_вікон(рч.get("hex"), с, вікна),
                              # ЩО КОД ЗНАЄ Й ДОСІ НЕ ПЕРЕДАВАВ. Ші не має доступу
                              # до каталогу (виклик API без `tools`), тож цей рядок —
                              # усе, що вона знає про річ.
                              тип=r.get("тип"),
                              # слово тканини ПЕРЕД родом: «вовна · полотно», а не «полотно»
                              тканина=(" · ".join(x for x in (r.get("волокно"), r.get("рід_тканини_слово"))
                                                  if x) or None),
                              деталі_крою=list(r.get("деталі_крою") or []),
                              крій=r.get("крій"),
                              каблук=r.get("каблук_словами"),
                              довжина=r.get("довжина_рівень"), рукав=r.get("рукав_слово"),
                              візерунок=r.get("візерунок"), блиск=r.get("блиск"),
                              халява=r.get("халява_рівень"), матеріал=r.get("матеріал_верху"),
                              тип_верхнього=r.get("тип_верхнього"),
                              капюшон=r.get("капюшон"), пояс=r.get("пояс"),
                              оверсайз=r.get("оверсайз"), простібка=r.get("простібка"),
                              бортність=r.get("бортність"),
                              також_у=(list(r.get("фото_сестри_колір") or [])
                                       if isinstance(r.get("фото_сестри_колір"), (list, tuple))
                                       else ([r["фото_сестри_колір"]] if r.get("фото_сестри_колір") else [])),
                              слоти_альт=tuple(x for x in (r.get("слоти_альт") or ())
                                               if x in _живі_слоти),
                              # ── РЕЄСТР ЯК МАТЕРІАЛ ДЛЯ МОДЕЛІ (K-REG-03) ──
                              # Тема-13: «кожен офер несе вектор реєстрів із балами;
                              # K-REG-01/02 отримують вхід». Код не будує образів —
                              # він віддає моделі те, з чого вона їх будує, і реєстр
                              # тут рівно такий матеріал: без нього модель не може
                              # виконати «один реєстр веде, другий — цитата».
                              # Порожньо — слів-маркерів не знайдено; це ЧЕСНЕ «не
                              # визначено», а не «річ поза реєстрами».
                              реєстр=(_РЕ_кандидата(r) or None),
                              гілка=r.get("_гілка") or "ядро", схема=r.get("_схема"),
                              # ПРАПОРЕЦЬ УТРИМАННЯ ПЕРЕЖИВАЄ ПЕРЕКЛАДАННЯ В РЯДОК
                              # (19.09.2026). Рядок кандидата будується тут з нуля, і
                              # мітка, поставлена на ЗАПИСІ пулу (`bridge._пакет_у_бюджет`
                              # на речах кольору, обраного жінкою), далі не їхала — а
                              # семплер працює саме над цими рядками. Поле службове
                              # (`_`), у пакет до моделі не йде: `_річ_пулу` збирає річ
                              # переліком ключів.
                              **({_СМ_.ПОЛЕ_УТРИМАННЯ: True} if r.get(_СМ_.ПОЛЕ_УТРИМАННЯ) else {}),
                              # чиє бажання річ виконує (рядок 159) — до `_річ_пулу`, яка
                              # кладе його в пакет поруч із рядком вимоги
                              **({"за_бажанням": r["за_бажанням"]} if r.get("за_бажанням") else {})))
        кандидати[с] = рядки
    _КЕШ_РЯДКІВ["ключ"] = (рез, вікна, тіло, K, _лічба)
    _КЕШ_РЯДКІВ["рядки"] = кандидати
    return {с: [dict(r) for r in рч] for с, рч in кандидати.items()}


def пакет_для_моделі(F, каталог, тіло, слоти=("верх", "низ", "взуття", "сумка"),
                     вікна=None, сценарій=None, K=None, рез=None, варіантів=1,
                     семплер=None, рамка=None, чистити=None, розвести_з=None, вже_були=None):
    """dict(кандидати, пакет, текст) — `текст` це ПАКЕТ_V1 у JSON, без ID правил.

    `рамка` — те в ПАКЕТ_V1, що не з пулу: `випадок`, `людина`, `правила`. Пул
    рахується тут, решту знає шов (`bridge._пакет_каталогу`), і зібрати об'єкт
    треба ДО зважування бюджету, бо бюджет міряє повний JSON, а не самий пул.
    `чистити` — функція шва, яка вирізає ID правил із рядків (`bridge._без_ід`):
    ID не забороняються моделі словами, їх просто нема чого називати.

    `розвести_з` — {слот: [id за позиціями]} ПУЛУ ІНШОЇ РУКИ ЦЬОГО Ж ПРОГОНУ
    (шов кладе туди пул руки 1, коли будує пул руки 2). Пул не звужується й не
    міняє складу — міняється лише те, ЯКА річ слота стоїть на якій позиції; див.
    `_розвести` нижче.

    `вже_були` — id речей із карток попередніх зборів цього сценарію (рядок 159):
    вони стають у кінець свого слота з позначкою `вже_був`; склад пулу той самий.
    """
    import composer as _КМ
    сценарій = dict(сценарій or {})
    if рез is None:
        рез = _КМ.зібрати(F, каталог, вікна=вікна, тіло=тіло, слоти=слоти, **сценарій)
    if not рез.get("зібрано"):
        return dict(готово=False, чому=рез.get("чому"), кандидати={}, текст="")
    кандидати = _рядки_кандидатів(тіло, вікна, K, рез)
    # ГРАФ І ВУЗОЛ ВЛАСНОГО ОБРАЗУ КОДУ БІЛЬШЕ НЕ БУДУЮТЬСЯ. Цей блок існував лише
    # заради рядка «ВУЗЬКЕ МІСЦЕ образу, який зібрав код» і полів `образ_коду` /
    # `портфель` у виході — усі троє прибрані 31.08.2026. Вузол над образом ШІ
    # рахує `перевірити_від_моделі`, і саме там йому місце.
    # ЗМІРЯНО ТОДІ Ж (щоб не вернулось): у промпт їхав вузол ВЛАСНОГО перебору
    # коду, і на 4 сценах × 2 сіди у 6 випадках із 8 напруга була ≤ 0.20 — рядок
    # сам собі казав «тут майже не тисне, міняти не обов'язково». Тобто 60 % часу
    # збирання виробляло 3 % промпта, порожнього в більшості сцен.
    # СЕМПЛЕР ПРАЦЮЄ НАД ЗІБРАНИМИ КАНДИДАТАМИ, А НЕ НАД СИРИМ ПУЛОМ: він має
    # бачити ті самі поля (тип, зона, гілка, магазин, ціна), за якими стратифікує,
    # а вони з'являються лише після `_у_річ`. Пара (функція, скільки).
    if семплер:
        _ф, _скільки, _сід = (list(семплер) + [0])[:3]
        кандидати = _ф(кандидати, _скільки, сід=_сід)
    # ── РЕЧІ ПОПЕРЕДНІХ ЗБОРІВ ПОСТУПАЮТЬСЯ (рядок 159) — після зрізу, щоб зріз
    # бачив той самий пул, що й без них, і до розведення рук, щоб рука 2 розводилась
    # від уже посунутого порядку руки 1.
    import різноманітність_пулу as _РП
    кандидати, _посунуто = _РП.посунути_вже_були(кандидати, вже_були)

    # ── ДВІ РУКИ ОДНОГО ПРОГОНУ НЕ ДІСТАЮТЬ ОДНАКОВОГО ПУЛУ ПОЗИЦІЙНО (рядок 62)
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ. Пули рук 1 і 2 — це та сама множина речей: вимір на
    # `каталог_brief.xml`, сід 5, 16 слотів — спільних речей 100 % у 15 слотах
    # (сумка 20 із 21), а на ОДНАКОВИХ позиціях стоїть від 0 до 21 речі зі слота
    # (сережки 10/10, сукня 8/8, верх 8/10). Тобто «рука 2 має власний сід»
    # (`bridge.СІЛЬ_РУКИ_2`, PR #92) розводить лише порядок РІВНИХ, а голови
    # списків лишаються тими самими — і будь-який детермінований читач пулу бере
