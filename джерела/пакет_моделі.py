# ── ВАРІАНТ «Б»: ПУЛ РУКИ 1 ЧАСТИНАМИ, ЗАПИТИ ПАРАЛЕЛЬНО (наряд К-3, доповнення 27.09) ──────
# ЧОМУ. Бюджет символів ріже пул до ~350 речей із ~1 840 придатних. Якщо той самий пул поділити
# на k частин і спитати k разів ОДНОЧАСНО, модель побачить у k разів більше речей, а жінка
# чекатиме стільки ж: виклики йдуть паралельно, і час на годиннику — це найдовший із них, а не
# сума. Власник: «Тестувальники вже скаржаться, що збір образів займає багато часу; дуже
# небажано його ще збільшувати».
# ЛИШЕ РУКА 1 (наряд): руки 2–4 не чіпаються — рука 2 будує свій пул проти пулу руки 1, а руки
# 3–4 каталогу не мають.
# ЧОМУ ПОДІЛ ПО КОЛУ ВСЕРЕДИНІ СЛОТА, а не «перші 1/k». Слот, відданий цілим одній частині,
# лишив би решту частин без взуття чи без сумки, і образ там не склався б узагалі. По колу
# кожна частина дістає ту саму частку кожного слота, тобто ті самі пропорції, що має пул.
# НОМЕРИ НЕ ПЕРЕНУМЕРОВУЮТЬСЯ: `н` роздано по ПОВНОМУ пулу (`номери_речей`), і відповідь
# будь-якої частини резолвиться проти того самого переліку кандидатів (`ід_з_тексту`).
# ОБРАЗІВ — ПОРІВНУ, залишок першим частинам: сума лишається тією, що просив показ.
def стала_пакета(пакет):
    """Скільки символів пакета НЕ залежать від пулу: випадок, людина, правила, задуми, шапка.

    Її платить КОЖЕН паралельний запит варіанту «б», тож бюджет пулу на `k` частин — це не
    `k × бюджет`, а `k × бюджет − (k−1) × стала`. Без цієї поправки перша ж проба показала
    частини по 133 000 символів там, де бюджет одного запиту 120 000.

    МІРЯЄТЬСЯ ДВОМА ПОВІДОМЛЕННЯМИ, А НЕ ПОРОЖНІМ ПУЛОМ: пакет без пулу зібрати не можна —
    `pool` оголошено обов'язковим (`СКЛАДАННЯ`, `збирач_промптів.зібрати`), і це правильно.
    Тому беруться повідомлення з ОДНІЄЮ і з ДВОМА речами: різниця — ціна речі, а перше
    мінус ця ціна — те, що не залежить від пулу зовсім."""
    речі = [r for рч in ((пакет or {}).get("пул") or {}).values() for r in (рч or [])]
    if len(речі) < 2:
        return len(промпт_складання(пакет or {}))
    один = len(промпт_складання(dict(пакет, пул={"_": речі[:1]})))
    два = len(промпт_складання(dict(пакет, пул={"_": речі[:2]})))
    return max(0, один - (два - один))


def частини_пакета(пакет, частин, чистити=None):
    """ПАКЕТ_V1 → `частин` повідомлень моделі над несуперечливими частинами того самого пулу.

    Частина — той самий пакет із тим самим випадком, людиною, правилами й задумами; різниця
    лише в переліку речей і в числі образів. `частин` ≤ 1 (або пул з однієї речі) → один
    текст, тобто рівно те, що робив би один виклик."""
    п = пакет or {}
    пул = п.get("пул") or {}
    k = max(1, int(частин or 1))
    усього = sum(len(рч or []) for рч in пул.values())
    if k < 2 or усього < 2:
        return [промпт_складання(п)]
    образів = int((п.get("завдання") or {}).get("образів") or 1)
    k = min(k, усього)
    тексти = []
    for і in range(k):
        шматок = {с: [r for j, r in enumerate(рч or []) if j % k == і] for с, рч in пул.items()}
        шматок = {с: рч for с, рч in шматок.items() if рч}
        част = dict(п, пул=шматок,
                    завдання=dict(п.get("завдання") or {},
                                  образів=образів // k + (1 if і < образів % k else 0)))
        # легенда реєстрів і порожні слоти лишаються від цілого пакета навмисно: вони
        # описують ВИПАДОК, а не вибірку, і перерахунок зробив би частини різними на смак
        тексти.append(промпт_складання(чистити(част) if чистити else част))
    return тексти


def скелет_схеми(вузол):
    """Форма відповіді — з ТОГО САМОГО оголошення, яким її потім перевіряють.

    ЧОМУ НЕ ЗРАЗОК, ПИСАНИЙ РУКАМИ. Доти форму диктував рядок у
    `_формат_відповіді`: другий опис того, що вже оголошено у валідаторі. Вони й
    розійшлися — там `"свідомо": ["<річ> — <чому>", …]` (список РЯДКІВ), а в
    `протокол.ОБРАЗ_МОДЕЛІ` це список ОБ'ЄКТІВ `{річ, чому}`. Тобто код просив
    одне, перевіряв інше, і винною виглядала модель. Скелет рахується зі схеми,
    тож розійтися нема з чим: зміниться схема — зміниться і те, що ми просимо.
    РОЗБІР ЗА СТРУКТУРОЮ ВУЗЛА, А НЕ ЗА СЛОВОМ ТИПУ: ключі `поля`/`по_ключу`/
    `елемент` однозначні, а назви типів (`обʼєкт` з U+02BC) — рівно те місце, де
    копія в другому модулі розходиться на один невидимий символ.
    """
    в = вузол or {}
    if "поля" in в:
        return {к: скелет_схеми(з) for к, з in (в.get("поля") or {}).items()}
    if "по_ключу" in в:
        return {"<ключ>": скелет_схеми(в.get("по_ключу"))}
    if "елемент" in в:
        return [скелет_схеми(в.get("елемент"))]
    if в.get("значення"):
        return "|".join(str(x) for x in в["значення"])
    return "<%s>" % (в.get("тип") or "будь_що")


def _нейтральний_тон(h, C, L=None):
    """Нейтраль за корпусом (K-COL-06) — ОДНЕ означення на всю систему.

    ВІДДАНО `колір_образу.нейтраль` (17.09.2026). Тут стояла ВЛАСНА копія коридорів
    («те саме означення, що в рядках вікон»), і вона розійшлась із тим, на що
    посилалась: `колір_образу.нейтраль` піднімає стелю хроми холодної нейтралі до
    34 для темних (L ≤ 45, зона нейві), а копія тримала 24 на будь-якій світлоті.
    Наслідок вимірюваний: темно-синя річ була нейтраллю для `feed.підходить`
    (рядок вікна пускав її як нейтраль) і КОЛЬОРОМ для `схема_образу` — тобто той
    самий образ давав гейт K-PAL-03 на речі, яку пул узяв рівно як законну під
    будь-яку схему нейтраль. Два означення нейтралі в одній системі — це не два
    пороги, а два різні вердикти на одній речі.
    `L` необов'язкова лише заради старих викликів із парою (h, C): без неї темна
    гілка нейві недосяжна, і це сказано тут, а не приховано дефолтом.
    """
    if C is None:
        return True
    import math as _м, колір_образу as _КО
    if L is None:
        L = 50.0                               # світлота не названа — середина шкали
    r = _м.radians(float(h or 0.0))
    lab = (float(L), float(C) * _м.cos(r), float(C) * _м.sin(r))
    return _КО.нейтраль(lab) is not None


def _сім_я_кута(h):
    """Назва сім'ї за кутом тону (`palettes.СІМ_Ї`); None — кут у жодній дузі.

    ВИНЕСЕНО З `_сім_я_тону` (17.09.2026): те саме питання ставить K-PAL-07
    («скільки кольорових сімей у великих слотах»), і там колір уже розкладений на
    осі — ганяти його назад у hex заради того самого циклу було б другим тілом
    одного правила. `СІМ_Ї` перекриваються навмисно (див. коментар над словником),
    і нічию тут бере перша оголошена — те саме, що робить `перекриття_сімей`
    правилом «порядок».
    """
    if h is None:
        return None
    import palettes as _ПЛ
    for ім, версії in _ПЛ.СІМ_Ї.items():
        for д in (версії.get("тепла"), версії.get("холодна")):
            if not д:
                continue
            lo, hi = д
            if (lo <= hi and lo <= h <= hi) or (lo > hi and (h >= lo or h <= hi)):
                return ім
    return None


def _сім_я_тону(hex_):
    """Назва сім'ї тону за `palettes.СІМ_Ї` для hex речі; None — нейтраль або не виміряно."""
    if not hex_:
        return None
    try:
        import colorspace as _КС
        L, C, h = _КС.lch(_КС.hx(hex_))
    except (TypeError, ValueError, AttributeError):
        return None
    if C is None or C < 10:
        return None
    return _сім_я_кута(h)


def _у_дузі_вікон(hex_, слот, вікна):
    """True/False — чи лежить тон речі в дузі котрогось кольорового вікна її слота
    (або річ нейтральна); None — колір не виміряно або слот без дуг."""
    if not hex_:
        return None
    рядки = [q for q in (вікна or []) if isinstance(q, dict) and q.get("слот") == слот]
    дуги = [(q["h_from"], q["h_to"]) for q in рядки if q.get("h_from") is not None and q.get("h_to") is not None and not q.get("нейтраль")]
    if not дуги:
        return None
    try:
        import colorspace as _КС
        L, C, h = _КС.lch(_КС.hx(hex_))
    except (TypeError, ValueError, AttributeError):
        return None
    if _нейтральний_тон(h, C, L):
        return True
    for lo, hi in дуги:
        lo, hi = float(lo), float(hi)
        if (lo <= hi and lo - 8 <= h <= hi + 8) or (lo > hi and (h >= lo - 8 or h <= hi + 8)):
            return True
    return False


