    # конкретній речі картки. Самих речей у пулі вже нема (`відсікти_пул`,
    # `ПРИЧИНА_НЕ_ЦЯ`), і без цього рядка модель не знає, чому їх нема: вона
    # законно бере з пулу їхнього близнюка тієї самої крамниці, і жінка вдруге
    # бачить те саме. Назви, а не id: id у пакет не їде взагалі.
    if рамка.get("не_ця"):
        обмеження["не_ця"] = [str(x) for x in рамка["не_ця"] if str(x or "").strip()]
    пакет["обмеження"] = обмеження
    if рамка.get("правила"):
        пакет["правила"] = рамка["правила"]
    пакет["полюси"] = полюси
    if _коди:
        # ЛЕГЕНДА МАГАЗИНІВ — ДАНІ, А НЕ ІНСТРУКЦІЯ. Прозою це був рядок «Магазини:
        # 00=gepur.com, …» усередині пулу; сам номер `н` без коду резолвиться в
        # ІНШУ річ іншого магазину, тож пара «номер·код» лишається обов'язковою.
        пакет["магазини"] = {к: м for м, к in _коди.items()}
    if _рз.get("слот"):
        пакет["розрив"] = {к: v for к, v in (("слот", _рз["слот"]),
                                             ("чому", _рз.get("чому") or "")) if v}
    # ФОРМУ ВІДПОВІДІ МУСИТЬ БУТИ ВИДНО З ПАКЕТА. Ім'я схеми («ОБРАЗИ_V1») моделі
    # нічого не каже: вона не має доступу ні до `протокол.py`, ні до історії — кожен
    # виклик іде свіжим контекстом. Тому поруч із іменем їде СКЕЛЕТ, порахований із
    # того самого оголошення, яким відповідь потім перевіряють (`скелет_схеми`).
    # Ім'я схеми — КЛЮЧ у `протокол.СХЕМИ`: описка падає тут KeyError-ом, а не
    # їде в пакет іменем, якого нема (enum того ж поля — `протокол.ВІД_МОДЕЛІ`).
    _відповідь = "ОБРАЗИ_V1"
    пакет["завдання"] = {"образів": int(варіантів or 1), "відповідь": _відповідь,
                         "схема_відповіді": скелет_схеми(_ПР.СХЕМИ[_відповідь]),
                         "вимоги": вимоги}
    if чистити:
        пакет = чистити(пакет)
    # `резонансні` тут БУЛО й знесено 08.09.2026: композитор кладе це поле лише під
    # прапорцем `вимір=N`, якого продукт не передає ніколи, тож у пакет воно їхало
    # порожнім завжди — і жоден споживач (bridge, показ, стенд) його не читав.
    return dict(готово=True, кандидати=кандидати, пакет=пакет,
                слоти_випали=рез.get("слоти_випали"), ноти_слотів=рез.get("ноти_слотів"),
                # ── ЧИСЛА ВІДСІВУ ВЕРХНЬОГО ШАРУ ЗА ФОРМАЛЬНІСТЮ (рядок 119) ──
                # Не в `пакет` (модель дістає ноту слота словами, і цього їй досить),
                # а ПОРУЧ із ним: читачі — `bridge.від_моделі`, який кладе це в сценарій
                # судді (K-WEA-01 регістру «питання» на картці), і повний звіт власника.
                шар_ошатності=рез.get("шар_ошатності"),
                # що посунуто як «вже було» і де поступитись нема кому (рядок 159)
                **({"різноманітність": _посунуто} if _посунуто else {}),
                текст=_json_.dumps(пакет, ensure_ascii=False, separators=(",", ":")))


