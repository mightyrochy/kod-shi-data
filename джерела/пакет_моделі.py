                ц = (" %s грн" % r["ціна"]) if r.get("ціна") else ""
                # ознаки ОДНІЄЇ речі, які не варто виносити в шапку групи
                хв = []
                if r.get("рукав"): хв.append("рукав: %s" % r["рукав"])
                if r.get("також_у"):
                    _ті = [x for x in r["також_у"] if x and x != "інший колір"][:3]
                    if _ті: хв.append("є також у: %s" % ", ".join(_ті))
