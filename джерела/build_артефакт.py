def _закриття(джерело, старт="bridge"):
    # ── AST, А НЕ РЕГУЛЯРКА (01.09.2026) ─────────────────────────────────────
    # СПІЙМАНО ЖИВИМ ПРОГОНОМ: тут стояло
    #     re.findall(r"^\s*(?:import|from)\s+([\w…]+)", т, re.M)
    # і воно брало ЛИШЕ ПЕРШЕ імʼя в рядку. `composer.py` має
    #     import outfit as O, feed, pipeline, profile as PR, coordination as КО
    # — регулярка бачила `outfit` і спинялась. feed/pipeline/profile вціліли
    # випадково, бо їх імпортують ще й окремими рядками; `coordination`
    # імпортується ТІЛЬКИ тут, тож у вантаж не потрапляв. В артефакті це давало
    # ModuleNotFoundError усередині `_пакет_у_бюджет`, який ловив його своїм
    # `except Exception` і віддавав ПОРОЖНІЙ пул. Далі промпт мовчки падав у
    # прозовий формат, модель писала прозу, і чотири прогони поспіль це
    # виглядало як «модель не тримає формат». Одна регулярка — і вся ланка
    # «код дає кандидатів → ші обирає id → код судить» не працювала ніколи.
    мод = {f[:-3] for f in os.listdir(джерело) if f.endswith(".py")}
    def імп(м):
        дерево = ast.parse(open(os.path.join(джерело, м + ".py"), encoding="utf-8").read())
        знайдені = set()
        for вузол in ast.walk(дерево):
            if isinstance(вузол, ast.Import):
                знайдені |= {а.name.split(".")[0] for а in вузол.names}
            elif isinstance(вузол, ast.ImportFrom) and вузол.level == 0 and вузол.module:
                знайдені.add(вузол.module.split(".")[0])
        return знайдені & мод
    треба, край = set(), {старт}
    while край:
        м = край.pop(); треба.add(м); край |= імп(м) - треба
    return треба


def _стрип(шлях):
    вих = []
    with open(шлях, "rb") as f:
        for т in tokenize.tokenize(f.readline):
            if т.type == token.COMMENT:
                continue
            вих.append(т)
    код = tokenize.untokenize(вих).decode("utf-8")
    код = _без_докстрінгів(код)
    return ("\n".join(р for р in код.splitlines() if р.strip()) + "\n").encode("utf-8")


def _без_докстрінгів(код):
    """Докстрінги теж геть — вантаж уперся в ліміт публікації (01.09.2026).

    ЧОМУ ЦЕ ЗʼЯВИЛОСЬ. Доданий у закриття `coordination.py` підняв артефакт із
    913 КБ до 932 КБ, і «Publish artifact» став «File is too large». Заміряно:
    модулі важать 1954 КБ стрипнутого коду проти 800 КБ каталогу, який
    стискається вчетирнадцятеро, — тобто вага саме в Python, а не у фіді.
    Зняття докстрінгів дає 1954 → 1496 КБ сирих, 616 → 465 КБ zip, тобто
    932 → 731 КБ html: нижче за 761 КБ, які точно публікувались.

    ЩО ЦЕ НЕ ЛАМАЄ. `__doc__` читають лише `build_артефакт.py` і `підфід.py` —
    обидва поза вантажем (перевірено grep'ом). Джерела в проєкті лишаються
    повними: стрипається КОПІЯ у вантажі, як і коментарі доти.

    ДВА ЗАПОБІЖНИКИ. Докстрінг лишається, якщо він ЄДИНИЙ у тілі (інакше тіло
    стає порожнім і файл не компілюється) і якщо він стоїть у тому ж рядку, що
    й `def` (`def f(): "doc"` — видалення рядка забрало б саму сигнатуру).
    """
    дерево = ast.parse(код)
    геть = set()
    for вузол in ast.walk(дерево):
        if not isinstance(вузол, (ast.Module, ast.FunctionDef,
                                  ast.AsyncFunctionDef, ast.ClassDef)):
            continue
        тіло = getattr(вузол, "body", None) or []
        if len(тіло) < 2 and not isinstance(вузол, ast.Module):
            continue
        п = тіло[0] if тіло else None
        if not (isinstance(п, ast.Expr) and isinstance(п.value, ast.Constant)
                and isinstance(п.value.value, str)):
            continue
        if getattr(вузол, "lineno", None) == п.lineno:
            continue
        геть |= set(range(п.lineno, п.end_lineno + 1))
    if not геть:
        return код
    return "\n".join(р for i, р in enumerate(код.splitlines(), 1) if i not in геть)


