# Показ переїжджає з ролі «екран вибору» в роль ЄДИНОЇ СТОРІНКИ: та сама
# сторінка міряє людину, дає обрати палітру, збирає образи й приймає вердикт.
# Отже вантаж має нести не 16 модулів шляху `палітри`, а всі, яких потребує
