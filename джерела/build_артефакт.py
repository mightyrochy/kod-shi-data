# Побічно це гейт — якщо `палітри` впала, збірка падає разом із нею.
#
# КАТАЛОГ У ВАНТАЖ ПОКАЗУ НЕ ЙДЕ. Виміряно: `палітри` працює без нього повністю
# (4 гілки, 11 основ). Речі — справа стенда.
