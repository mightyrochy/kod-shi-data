"""Спільні обмеження, цілі та походження кандидатів відбору."""
import реєстр_намір as _РН
import json as _json
import random as _random


def ідентичність(значення):
    """Стійкий ключ речі, образу або службової групи без позиції у списку."""
    if isinstance(значення, dict):
        for поле in ('id', 'ід', 'н'):
            if значення.get(поле) is not None:
                return str(значення[поле])
    if isinstance(значення, (tuple, list)):
        return _json.dumps([ідентичність(v) for v in значення], ensure_ascii=False)
    return _json.dumps(значення, sort_keys=True, ensure_ascii=False, default=str)


def порядок(значення, сід=0, мітка=''):
    """Впорядкувати за ід, тоді перемішати сталим сідом у межах заданого ярусу."""
    вих = sorted(значення, key=ідентичність)
    if сід:
        _random.Random('%d|%s' % (сід, мітка)).shuffle(вих)
    return вих


def ключ_образу(образ, неприйнятний, гейт, склад=None):
    """Спільна мета запасного вибору й ремонту: придатність, повнота, стійкий ід.

    Смак і намір оцінює стилістка за goals. Код упорядковує лише її варіанти
    за відомими обмеженнями, зберігаючи найбільше її речей за рівних обмежень.
    """
    блокери = (образ.get('структура') or {}).get('блокери') or []
    гейти = sum(z.get('регістр') == 'гейт' and not z.get('свідомий')
                for z in образ.get('знахідки') or [] if isinstance(z, dict))
    return (bool(неприйнятний), bool(гейт), гейти, len(блокери),
            -len(склад if склад is not None else образ.get('речі') or []),
            ідентичність(образ))


def опис(намір="conventional", мета_важливо=None):
    """Описати незалежні обмеження й цілі через чинний реєстр намірів."""
    н = _РН.канон_намір(намір)
    return dict(constraints=dict(gates="required", veto="required", doses="independent"),
                goals=dict(intent=н, intent_rules=_РН.намір(н, мета_важливо),
                           edge="inside_palette", pole="preserve", band="occasion"),
                order="identity")


def намір(код, мета_важливо=None):
    """Прочитати судові цілі з того самого опису, що бачить стилістка."""
    return опис(код, мета_важливо)["goals"]["intent_rules"]


def на_дріт(політика):
    """Залишити коди й числа політики, без внутрішніх підписів реєстру."""
    ц = політика["goals"]
    н = ц["intent_rules"]
    return dict(політика, goals=dict({к: v for к, v in ц.items() if к != "intent_rules"},
                                    count_limits=н["рахункові"],
                                    bold_branches=н["сміливі_гілки"]))


def з_дозою(річ, гілка, ціль):
    """Додати незалежну дозу, зберігши вже призначені іншим осям цілі."""
    д = dict(річ.get("_дози") or {})
    д[гілка] = int(ціль)
    return dict(річ, _дози=д)


def дози(річ):
    """Прочитати незалежні дози або старий запис однієї дози."""
    if not isinstance(річ, dict):
        return {}
    if "_дози" in річ:
        return річ["_дози"]
    return ({річ.get("_гілка_дози") or річ.get("гілка") or річ.get("_гілка") or "ядро":
             int(річ["_доза"])} if "_доза" in річ else {})


def без_доз(річ):
    """Прибрати лише службові обмеження для внутрішнього стратифікованого добору."""
    return {к: v for к, v in річ.items() if к not in ("_дози", "_доза", "_гілка_дози")}


def дози_на_дріт(річ):
    """Передати причину присутності речі та її дозу кодами незалежних осей."""
    коди = {"на межі": "edge", "нижче смуги": "below_band", "блиск": "shine", "розрив": "break"}
    return {коди[г]: n for г, n in дози(річ).items() if г in коди}
