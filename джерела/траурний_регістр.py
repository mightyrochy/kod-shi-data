# «лакована шкіра» — лак, а не шкіра.
МАТЕРІАЛ_НАЗВИ = (
    ("лак", r"\bлаков(?:а|ий|е|і)\b|\bлакован(?:а|ий|е|і)\b|\b(?:з|із)\s+лаку\b"),
    ("атлас", r"\bатласн(?:а|ий|е|і)\b|\bсатинов(?:а|ий|е|і)\b|\b(?:атлас|сатин)\b"
              r"|\b(?:з|із|зі)\s+(?:[^\s,()]+\s+){0,2}?(?:атласу|сатину)\b"),
    ("шкіра", r"\b(?:з|із|зі)\s+(?:[^\s,()]+\s+){0,2}?(?:еко[- ]?)?шкір[иі]\b"
              r"|\b(?:еко-?)?шкірян(?:а|ий|е|і)\b|\bшкірзам\b|\b(?:еко)?шкіра\b"),
)
# ПОВЕРХНЯ, ЯКУ МАТЕРІАЛ КАЖЕ САМ: шкіра й лак (`verify.СЛОВО_ТКАНИНИ` — leather, patent)
# і атлас (satin), і слова фото-читача, якими він бачить ту саму поверхню (нубук він пише
# окремо, «лак» — іменником). Волокно поверхні не каже: шовк буває і крепом, і атласом,
# і оксамитом («Velvet midi dress» ж-01173@morandi — волокно «шовк», фото «вельвет»), тож
# розбіжністю свідків шовк і фото-слово іншого плетіння не є.
ПОВЕРХНЯ_ЗА_ФОТО = {"leather": ("шкіра", "екошкіра", "лак", "замша", "нубук"),
                    "patent": ("шкіра", "екошкіра", "лак", "замша", "нубук"),
                    "satin": ("атлас", "сатин")}


def траур_випадку(нагода=None, місце=None, траур=None):
    """Чи діє траурний регістр — і як: ПОДІЯ чи СТАН. None — не діє.

    Повертає dict(подія, лишилось, період, минуло, зв_язок, чому). ПОДІЯ — місце
    «похорон» або траур без названої тривалості (стан оголошено ЗАРАЗ, залишок
    повний — той самий аргумент, що в K-OCC-01 з 17.09): `лишилось` = 1.0. СТАН —
    названо, скільки минуло: `лишилось` спадає за `ТРАУР_ПЕРІОД` до нуля, і нуль —
    теж відповідь («стан скінчився»), а не None: людина ж траур назвала."""
    т = dict(траур) if isinstance(траур, dict) else {}
    на_похороні = місце in МІСЦЯ_ПОДІЇ_ТРАУРУ
    if not (на_похороні or нагода == "траур" or т):
        return None
    зв = т.get("зв'язок") or т.get("звязок") or "далекі"
    період = ТРАУР_ПЕРІОД.get(зв, 3)
    _місяців_є = т.get("місяців") not in (None, "")
    минуло = float(т.get("місяців") or 0) if _місяців_є else None
    подія = на_похороні or not _місяців_є
    лишилось = 1.0 if подія else max(0.0, 1.0 - минуло / max(1e-6, період))
    чому = ("сам похорон: дрес-код події, спаду нема" if на_похороні
            else "траур оголошено нагодою, тривалості не названо — стан ЗАРАЗ, залишок повний"
            if подія else "стан трауру: минуло %.0f міс із %d — залишок %.2f" % (минуло, період, лишилось))
    return dict(подія=подія, лишилось=round(лишилось, 3), період=період, минуло=минуло,
                зв_язок=зв, чому=чому)


# ТРАУР — ЗАЯВА ЛЮДИНИ, А НЕ НАГОДА ПОЛОМКИ (рядок 154). Корпус K-OCC-01: «FORCE: `hard`
# on the person's declaration». Поломка руки 2 «доречність» зсуває нагоду на 1–2 щаблі
# ошатності (`міст_рука2._зіпсувати_сценарій`), і за таблицею місць сусідом «роботи» стає
# й «траур». ВИМІРЯНО на стенді (офіс, 12 сідів): на сідах 2 і 5 поломка — «доречність:
# робота → траур», і з регістром, що йшов за нагодою пулу, рука 2 в офісний день діставала
# траурний пул і рядки «На похорон…». Навпаки, на похороні (сід 5) та сама поломка
# «траур → формал_вечір» знімала регістр зовсім. Тепер шов кладе в сцену руки 2
# `траур_заяви` — поля нагоди, як їх сказала людина, — і регістр вмикає лише вона:
# поломка й далі зсуває ошатність, але трауру не оголошує й не скасовує.
ПОЛЯ_ЗАЯВИ_ТРАУРУ = ("нагода", "місце", "траур")


def заява_трауру(сцен):
    """Що людина сама сказала про траур: поля `ПОЛЯ_ЗАЯВИ_ТРАУРУ` її сценарію, без порожніх."""
    с = сцен if isinstance(сцен, dict) else {}
    return {к: с.get(к) for к in ПОЛЯ_ЗАЯВИ_ТРАУРУ if с.get(к) not in (None, "")}


def з_заявою(сц2, сц_людини):
    """Сцена руки 2 із заявою людини про траур (`траур_заяви`) — лише коли поломка змінила
    поля заяви; інакше та сама сцена, байт у байт (година, температура, донор…)."""
    з = заява_трауру(сц_людини)
    if заява_трауру(сц2) == з:
        return сц2
    return dict(сц2 or {}, траур_заяви=з)


def траур_сцени(сцен):
    """`траур_випадку` для сцени пулу чи суду — за заявою людини, коли шов її поклав.

    `траур_заяви` у сцені — заява людини (`заява_трауру`), яку шов кладе руці 2, коли її
    поломка змінила нагоду; без ключа — поля самої сцени (рука 1, руки 3–4, CLI)."""
    с = сцен if isinstance(сцен, dict) else {}
    з = с.get("траур_заяви") if isinstance(с.get("траур_заяви"), dict) else с
    return траур_випадку(з.get("нагода"), з.get("місце"), з.get("траур"))


def поза_траурним_регістром(L, C):
    """(над_L, над_гучності) — на скільки колір вийшов за «темне й тихе»; (0, 0) — у регістрі.

    Тиша — гучність C*·L*/50 (мірило весілля), стеля — у куті `НАГОДА["траур"]`:
    стеля_хроми × L_макс / 50. На L* = L_макс межа хроми та сама, що доти; темніше —
    допускається глибший колір (темно-синій, бордо), світліше — вихід за L_макс."""
    оп = НАГОДА["траур"]
    стеля_г = оп["стеля_хроми"] * оп["L_макс"] / 50.0
    return max(0.0, float(L) - оп["L_макс"]), max(0.0, float(C) * float(L) / 50.0 - стеля_г)


def _грубість_трауру(L, C):
    """Сила виходу за регістр 0…1 — та сама шкала, що в K-OCC-01 доти.

    Знаменник гучності — 25 × L_макс/50: на L* = L_макс він дає рівно старе
    «над_C / 25», тож на межі регістру сила не стрибнула від зміни мірила."""
    оп = НАГОДА["траур"]
    над_L, над_Г = поза_траурним_регістром(L, C)
    return min(1.0, над_Г / (25.0 * оп["L_макс"] / 50.0) + над_L / 30.0)


def траурний_регістр_речі(r):
    """Де колір речі стоїть щодо траурного регістру.

    dict(стан, частка, свідок, слово, L, C, чому, грубість): `стан` «так» — у регістрі
    (вимір або ВСІ прочитання слова), «здебільшого» — колір лише словом і більшість
    його прочитань у регістрі, «ні» — поза (вимір або більшість прочитань), None —
    кольору нема зовсім: незнання не відсівається. `грубість` — для виміряного кольору
    сила виходу; для слова — НАЙМЕНША по вузлах вікна (чесна нижня межа)."""
    нв = r.get("колір_не_вимір") if isinstance(r.get("колір_не_вимір"), dict) else {}
    вікно = нв.get("вікно") or (r.get("вікно") if r.get("джерело_кольору") == "назва_вікно" else None)
    if вікно:
        import verify as _V
        # сітка — та сама, що в частки вікна палітри (`feed._ЧАСТКА_СІТКА`), через
        # фасад: два літерали розійшлися б на першій же правці однієї з них
        import feed as _Ф

        def _частка(в):
            """(частка вузлів вікна в регістрі, найменша грубість по вузлах)."""
            nL, nC = _Ф._ЧАСТКА_СІТКА[0], _Ф._ЧАСТКА_СІТКА[1]
            Llo, Lhi, Clo, Chi = (float(x) for x in в[:4])
            г = [_грубість_трауру(Llo + (Lhi - Llo) * (i + 0.5) / nL, Clo + (Chi - Clo) * (j + 0.5) / nC)
                 for i in range(nL) for j in range(nC)]
            return round(sum(1 for x in г if x <= 0.0) / len(г), 3), min(г)
        слово = нв.get("слово") or r.get("колір_ім") or r.get("колір_назва") or "?"
        # МОДИФІКАТОР СВІТЛОТИ З НАЗВИ ТОВАРУ — ТИМ САМИМ МЕХАНІЗМОМ, ЩО В ПОЛІ КОЛЬОРУ
        # (`verify.модифікатор_світлоти`: «темно-»/«світло-» перед коренем звужує L-вікно
        # до його половини). Поле кольору модифікатора часто не несе, а назва — несе:
        # ж-00055@alot «Сукня світло-коричнева» з полем «коричневий», ж-09763@attico
        # «колір темно-коричневий» з полем «коричневий». Без цього обидві судились би
        # однією «коричневою» половиною навпіл.
        _мод = None if r.get("колір_модифікатор") else _V.модифікатор_світлоти(
            str(r.get("назва") or ""), слово if слово in _V.ЛЕКСИКОН else None)
        if _мод:
            _сер = (float(вікно[0]) + float(вікно[1])) / 2.0
            вікно = ((вікно[0], _сер) if _мод == "темно" else (_сер, вікно[1])) + tuple(вікно[2:])
        частка, найменша = _частка(вікно)
        чому = "колір лише словом «%s»%s: темні й тихі %d %% його прочитань" % (
            слово, (" (у назві — «%s-»)" % _мод) if _мод else "", round(100 * частка))
        # ДВА СВІДКИ, І ТЕМНИМ КОЛІР БУВАЄ ЛИШЕ ЗА ЗГОДИ ОБОХ. У спорі кольору слово
        # крамниці лишається кольором речі (ПЕРЕДАЧА §5), але твердження «ця річ
        # темна й тиха» слово з фото може заперечити — і тоді частка береться менша
        # з двох. Виміряно на похороні (сід 3): ж-00741@diadia «коричневий» на фото
        # «кемел», ж-00645@alot «коричневий» на фото «хакі» — обидві йшли в пул як
        # «здебільшого темні».
        _сп = r.get("колір_спір") if isinstance(r.get("колір_спір"), dict) else {}
        _вікно_фото = _V.ЛЕКСИКОН.get(str(_сп.get("модель") or ""))
        if _вікно_фото and _сп.get("модель") != слово:
            _ч2, _н2 = _частка(_вікно_фото)
            if _ч2 < частка:
                частка, найменша = _ч2, max(найменша, _н2)
                чому += "; фото каже «%s» — темні й тихі лише %d %% його прочитань" % (
                    _сп["модель"], round(100 * _ч2))
        стан = ("так" if частка >= 1.0 else
                "здебільшого" if частка > ЧАСТКА_БІЛЬШОСТІ_ТРАУРУ else "ні")
        return dict(стан=стан, частка=частка, свідок="слово", слово=слово,
                    L=tuple(вікно[:2]), C=tuple(вікно[2:4]), грубість=найменша, чому=чому)
    lab = r.get("lab")
    if not lab:
        return dict(стан=None, частка=None, свідок=None, слово=None, L=None, C=None,
                    грубість=None, чому="кольору нема — незнання не відсівається")
    import colorspace as _КС
    L, C, _h = _КС.lch(tuple(lab))
    г = _грубість_трауру(L, C)
    чому = "виміряно L*%.0f C*%.0f — %s" % (L, C, "темне й тихе" if г <= 0.0 else
                                            "світле або яскраве для трауру")
    # ДРУГИЙ КОЛІР ВІЗЕРУНКА — ДРУГИЙ СВІДОК. `lab` запису — колір, яким речі дали ім'я:
    # у ж-11629@theoriginals «Шкіряна сумка в смугастий принт» це графіт (39 % площі
    # фото), а вершкової смуги — 61 %. Коли візерунок названо, другий колір фото лежить
    # на самій речі, і темною вона буває лише за згоди обох кольорів. Без візерунка —
    # ні: там другий колір фото — тло чи інша річ на моделі. ВИМІРЯНО на каталог_повний:
    # серед речей регістру з темним іменем і світлою більшою площею однотонних і без
    # візерунка 27, і це чорні ж-11125@theoriginals «Чорна облягаюча спідниця» (світла
    # площа 94 %), ж-11044@skripka «Сумка DANDY чорна» (85 %) — тло, а не річ.
    кк = [c for c in (r.get("colors") or []) if isinstance(c, dict) and c.get("lab")]
    if len(кк) >= 2 and г <= 0.0 and r.get("візерунок") not in (None, "", "solid"):
        осн = max(кк, key=lambda c: float(c.get("coverage") or 0.0))
        L2, C2, _h2 = _КС.lch(tuple(осн["lab"]))
        г2 = _грубість_трауру(L2, C2)
        if г2 > 0.0:
            L, C, г = L2, C2, г2
            чому += "; колір найбільшої площі (%d %%) — L*%.0f C*%.0f, світле або яскраве для трауру" % (
                round(100 * float(осн.get("coverage") or 0.0)), L2, C2)
    return dict(стан=("так" if г <= 0.0 else "ні"), частка=None, свідок="вимір",
                слово=r.get("колір_назва"), L=L, C=C, грубість=г, чому=чому)


def основний_колір(r, e):
    """Чи елемент суду `e` — ОСНОВНИЙ колір запису `r` (той, яким його судив пул).

    Запис без `colors` дає рівно один елемент — він і є основний. З `colors` основний
    — колір із найбільшим покриттям; елемент несе lab, виведений із hex (заокруглений),
    тож рівність — допуском ΔE00 < 1, а не байтом."""
    кк = [c for c in (r.get("colors") or []) if isinstance(c, dict)]
    if len(кк) < 2:
        return True
    import colorspace as _КС
    осн = max(кк, key=lambda c: float(c.get("coverage") or 0.0))
    lab = осн.get("lab") or (_КС.hx(осн["hex"]) if осн.get("hex") else None)
    return bool(lab and e.get("lab")) and _КС.de00(tuple(lab), tuple(e["lab"])) < 1.0


def _прикраса_не_з_металу(r):
    """Прикраса без названого металу: обруч, заколка, бант, резинка, кліпси — тканина чи
    пластик біля обличчя, навіть коли тип прочитано криво (ж-07573 — «джинси»)."""
    return r.get("слот") == "прикраси" and not r.get("метал")


def регістрова_річ(r):
    """Чи міряє траурний регістр колір цієї речі: слоти `СЛОТИ_ТРАУРНОГО_РЕГІСТРУ`, тип
    `ТИПИ_ТРАУРНОГО_РЕГІСТРУ` і прикраса не з металу. Метал — ні: його вибирає жінка (п.9)."""
    return (r.get("слот") in СЛОТИ_ТРАУРНОГО_РЕГІСТРУ
            or str(r.get("тип") or "") in ТИПИ_ТРАУРНОГО_РЕГІСТРУ
            or _прикраса_не_з_металу(r))


def біля_обличчя(r):
    """Чи річ біля обличчя для «no shine near the face»: `БІЛЯ_ОБЛИЧЧЯ_ТРАУРУ`, обруч і
    прикраса не з металу. Низ, взуття, сумка й пояс — ні."""
    return (r.get("слот") in БІЛЯ_ОБЛИЧЧЯ_ТРАУРУ
            or str(r.get("тип") or "") in ТИПИ_ТРАУРНОГО_РЕГІСТРУ
            or _прикраса_не_з_металу(r))


def матеріал_крамниці(r):
    """(матеріал, за_чим, слова) — що крамниця каже про матеріал самої речі; три None — мовчить.

    Слово назви про саму річ (`МАТЕРІАЛ_НАЗВИ`) — першим: `волокно` буває підкладкою
    («Пряма дублянка зі шкіри ягняти» ж-11340 — волокно «шовк»). Коли назва мовчить —
    `волокно`, але не те, яке дописало фото (`волокно_джерело` «фото»): це вже не другий свідок.
    `слова` — ті слова крамниці, якими вона це каже («з екошкіри»), для пояснення."""
    import re as _re
    н = str(r.get("назва") or "").lower()
    for м, р in МАТЕРІАЛ_НАЗВИ:
        зб = _re.search(р, н)
        if зб:
            return м, "назва", зб.group(0)
    if r.get("волокно") and r.get("волокно_джерело") != "фото":
        return r["волокно"], "волокно", r["волокно"]
    return None, None, None


def клас_блиску(м):
    """(блиск 0–3 або None, тканина або None) матеріалу `м` за якорями корпусу.

    Читає `verify.тканина_зі_слова` — ту саму шкалу, що дає `блиск` слову назви. «Лак»
    крамниці й фото — іменник, а корінь `СЛОВО_ТКАНИНИ` — прикметник «лаков»."""
    import verify as _V
    т = _V.тканина_зі_слова({"лак": "лакова"}.get(м, м) if м else "")
    return т.get("блиск"), т.get("тканина")


def свідки_блиску(r):
    """Що кажуть про блиск речі два незалежні свідки — крамниця і фото.

    dict(крамниця, за_чим, слова, клас, фото, блиск, згода, розходяться, чому): `слова` — чим
    крамниця це каже (`матеріал_крамниці`), `клас` — блиск
    матеріалу крамниці за якорями корпусу (`клас_блиску`), `фото` і `блиск` — `матеріал_фото`
    і число фото, `згода` — фото бачить ту саму поверхню (`ПОВЕРХНЯ_ЗА_ФОТО`). `розходяться`
    — крамниця каже шкіру, лак чи атлас, а фото цієї поверхні не бачить: або називає інший
    матеріал (тоді число фото міряло не цю річ), або, коли крамниця каже блиск за самим
    матеріалом (атлас, лак — клас 2), не називає нічого і блиску не бачить. Блиску тоді ніхто
    не виміряв. Замша (клас 0) матова за самим матеріалом — там розбіжність про блиск нічого
    не каже (ж-12153 «Замшевий жакет»); шкіра, про яку фото мовчить, — теж: м'який люстр
    за якорем — фон, і число фото йому не суперечить."""
    м, за_чим, слова = матеріал_крамниці(r)
    клас, тк = клас_блиску(м)
    мф = r.get("матеріал_фото")
    згода = bool(мф and мф in ПОВЕРХНЯ_ЗА_ФОТО.get(тк, ()))
    розх = bool(тк in ПОВЕРХНЯ_ЗА_ФОТО and (клас or 0) >= 1 and not згода
                and (мф or (клас or 0) >= БЛИСК_ГЛЯНЕЦЬ))
    return dict(крамниця=м, за_чим=за_чим, слова=слова, клас=клас, фото=мф, блиск=r.get("блиск"),
                згода=згода, розходяться=розх,
                чому=(None if not розх else "%s каже «%s», %s" % (
                    "назва" if за_чим == "назва" else "крамниця", слова,
                    "фото прочитало «%s»" % мф if мф
                    else "фото матеріалу не назвало і блиску не бачить (%s)" % r.get("блиск"))))


def святкова_оздоба(r):
    """Назва святкової оздоби речі словами крамниці, або None (`СВЯТКОВІ_ОЗДОБИ`).

    Обруч і прикраса не з металу — ще й словом оздоби (`_ОЗДОБЛЕНИЙ_ОБРУЧ`) або
    візерунком «квітковий» чи «вишивка» (слово крамниці або фото)."""
    import re as _re
    текст = " ".join(str(r.get(k) or "") for k in ("назва", "тканина", "деталі_крою",
                                                   "матеріал", "тип")).lower()
    for ім, р in СВЯТКОВІ_ОЗДОБИ:
        if _re.search(р, текст):
            return ім
    обруч = str(r.get("тип") or "") in ТИПИ_ТРАУРНОГО_РЕГІСТРУ
    # бант як сама прикраса (ж-07554 «Бант з костюмної тканини») — предмет, а не оздоба на ньому
    оздоба = (_ОЗДОБЛЕНИЙ_ОБРУЧ.replace("|бант", "") if r.get("тип") == "бант" else _ОЗДОБЛЕНИЙ_ОБРУЧ)
    if (обруч or _прикраса_не_з_металу(r)) and (
            _re.search(оздоба, текст)
            or str(r.get("візерунок") or "") in ("квітковий", "вишивка")):
        return "оздоблений обруч" if обруч else "оздоблена прикраса"
    return None


def траурне_відсічення(r, тр):
    """Причина зняти річ з пулу траурної нагоди, або None. `тр` — `траур_випадку`.

    Одна функція на всіх, хто кладе речі в пул рук 1–2: абсолютні фільтри
    композитора, добір обов'язкового слота, пошук речі за запитом моделі. Повз
    неї свідомо йдуть лише слова жінки — її бажання й обрана основа (п.9: явний
    вибір сильніший за гейт коду). Стан, що скінчився (`лишилось` 0), не знімає нічого."""
    if not тр or not тр.get("лишилось"):
        return None
    оз = святкова_оздоба(r)
    if оз:
        return "святкова оздоба (%s)" % оз
    if r.get("візерунок") in ГУЧНІ_ВІЗЕРУНКИ_ТРАУРУ:
        if r.get("слот") in ВЕЛИКІ_ПОВЕРХНІ_ТРАУРУ:
            return "гучний візерунок на великій поверхні (%s)" % r["візерунок"]
        if біля_обличчя(r):
            return "гучний візерунок біля обличчя (%s)" % r["візерунок"]
    бл = r.get("блиск")
    if isinstance(бл, (int, float)) and бл >= БЛИСК_ГЛЯНЕЦЬ and біля_обличчя(r):
        return "блиск біля обличчя (атлас, лак чи металік)"
    if регістрова_річ(r):
        рг = траурний_регістр_речі(r)
        if рг["стан"] == "ні":
            return ("колір поза регістром за словом" if рг["свідок"] == "слово"
                    else "колір поза регістром за виміром")
    # другий свідок блиску може лише посилити (рядок 163): атлас, сатин чи лак за словом
    # крамниці — блиск за самим матеріалом, хай яке число дало фото. Слово назви про саму
    # річ свідчить саме; `волокно` — лише за згоди фото: воно буває підкладкою чи деталлю
    # (ж-02985@ricamare «Приталений піджак» — волокно «сатин», на фото матовий костюм), і
    # тоді суд ставить «питання» (`свідки_блиску` → «розходяться»). Причина — останньою, як
    # дощ у композиторі (рядок 161): лічба `відсічено` показує лише те, що зняв цей свідок.
    if біля_обличчя(r):
        св = свідки_блиску(r)
        if (св["клас"] or 0) >= БЛИСК_ГЛЯНЕЦЬ and (св["за_чим"] == "назва" or св["згода"]):
            return "блиск біля обличчя (%s — %s крамниці)" % (
                св["крамниця"], "слово назви" if св["за_чим"] == "назва" else "волокно")
    return None
