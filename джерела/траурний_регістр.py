# браслети (рожеві, бежевий), п'ять пар сережок (кемел, зелені, червоні, сірі, білі), три
# світлі підвіски й кліпси, кораловий чокер, каблучка з синім кристалом; лишились 20 —
# чорна брошка з органзи, чорні сережки й кольє, перли, срібні за кольором сережки.
# Перлину код від іншої прикраси не відрізняє — коду «перли» нема, слова назви не читаються (рядок 5194).


def _прикраса_кольором(r):
    """Ювелірна річ поза слотом «прикраси» без названого металу, чий колір — не метал."""
