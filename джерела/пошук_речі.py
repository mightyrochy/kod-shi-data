# -*- coding: utf-8 -*-
"""пошук_речі.py — «знайди мені таку»: опис речі кодами → записи каталогу, що відповідають КОЖНОМУ коду опису, з
оцінкою для неї.

ЧОМУ (слова власника 12.11, 14:13 — «Якщо людина попросить люстерко знайти їй наприклад спідницю з паєтками, чи видасть
люстерко варіанти які є в її каталозі?», 14:18 — «Так.»; наряд «Функція-купити-річ», сценарій Б). Доти пошуку речі з
розмови не було зовсім (дошка 2980): у каталозі є 18 спідниць із паєтками, а Люстерко не мало як їх показати.

ХТО ЩО РОБИТЬ (п.12). Її слова розуміє мовна модель розмови й кличе інструмент `find_item` (`conversation_tools`) з
кодами: вид, колір, довжина, крій, візерунок, фактура, блиск. Код слів не читає: добирає записи каталогу за кодами
розбору фіду (`ЧИТАЧІ` — поле запису → код внутрішньої мови) і звіряє КОЖЕН названий код. Нема запису, що відповідає
всім, — пряме «нема» (`catalogue_has_none`), без підміни схожим. Запис без поля, яке вона назвала, — не варіант: код не
знає, чи відповідає він опису; скільки таких, каже `catalogue_records_without_code` (каталог тут не дорозбирається).

ОЦІНКА ВАРІАНТА — ТОЙ САМИЙ СУД, ЩО Й РЕЧІ З ФОТО (`річ_з_фото.вердикт`, запис каталогу — аргументом `запис`): край на
її тілі, посадка, крій, роль кольору, з чим він поєднується, куди веде погляд (`суд_покупки`). Порядок варіантів і
котрий радить першим — `суд_покупки.вибір`, той самий, що для кількох речей з фото."""
import json as _json
import asyncio as _asyncio
import time as _time

import внутрішня_мова as _ВМ
import verify as _V
from реєстр_правил import ТИПОВИЙ_НАМІР
# Суд, каталог і вхід моста — у функціях: переліки кодів звідси читає `conversation_tools` (промпт ходу), а суд речі
# сам тягне мовний шар — на рівні модуля це коло імпортів.

U = _ВМ.UNKNOWN

# Шкала блиску каталогу (`verify.СЛОВО_ТКАНИНИ`, жнива: 0 матове, 1 легкий люстр, 2 явний глянець, 3 паєтки/стрази) —
# кодами: поле запису `блиск` уже число цієї шкали.
БЛИСК = {"matte": 0, "soft_lustre": 1, "gloss": 2, "sequins_rhinestones": 3}
# Фактура — коди фактур, які знає код каталогу (`verify.СЛОВО_ТКАНИНИ`), дефіс → підкреслення (коди внутрішньої мови).
ФАКТУРИ = sorted({т.replace("-", "_") for т, _ in _V.СЛОВО_ТКАНИНИ.values() if т})
# Довжина: коди мови (`ТАБЛИЦЯ["length"]`); клас довжини запису (`довжина_рівень`) — точка речі тієї самої таблиці, якою
# річ з фото йде в `довжина_рівень` (`річ_з_фото.ДОВЖИНИ_МОДЕЛІ`, «міді» → «литка»).
ДОВЖИНИ = sorted(_ВМ.ТАБЛИЦЯ["length"])


def клас_довжини(код):
    """Код довжини мови → клас довжини запису каталогу (None — код поза таблицею)."""
    import річ_з_фото as _РФ
    return next((_РФ.КЛАС_СЛОВА[с] for с, к, _т in _РФ.ДОВЖИНИ_МОДЕЛІ if к == код), None)


def _колір(з):
    """Код кольору запису: слово крамниці лексиконом (`колір_ім`), а коли колір виміряно — саме слово крамниці."""
    return _ВМ.код("color_name", з.get("колір_ім")) or _ВМ.код("color_name", з.get("колір_назва"))


# Аргумент інструмента → (читач коду запису, перелік кодів). Читач — None: у запису коду нема.
ЧИТАЧІ = {
    "item_type": (lambda з: _ВМ.код("item_type", з.get("тип")), sorted(_ВМ.ТАБЛИЦЯ["item_type"])),
    "colour": (_колір, sorted(_ВМ.ТАБЛИЦЯ["color_name"])),
    "length": (lambda з: з.get("довжина_рівень") or None, ДОВЖИНИ),
    "cut": (lambda з: з.get("крій") or None, None),
    "pattern": (lambda з: (_ВМ.код("pattern", з.get("візерунок")) or None), sorted(_ВМ.ТАБЛИЦЯ["pattern"])),
    "texture": (lambda з: (з.get("текстура") or "").replace("-", "_") or None, ФАКТУРИ),
    "shine": (lambda з: next((к for к, б in БЛИСК.items() if б == з.get("блиск")), None), list(БЛИСК)),
}


def _збіг(код_запису, хоче, поле):
    """Чи код запису — те, що вона назвала; довжина — клас запису проти класу її коду («mid_thigh» і «mini» — та сама
    точка, `ДОВЖИНИ_МОДЕЛІ`)."""
    if поле == "length":
        return код_запису is not None and код_запису == клас_довжини(хоче)
    return код_запису == хоче


def знайти(каталог, опис):
    """(варіанти, без_коду) — записи, що відповідають КОЖНОМУ коду `опис`, і {поле: скільки записів того самого
    виду не мають коду цього поля}. Коди поза переліком і «unknown» — не умова (модель її не назвала)."""
    умови = {п: к for п, к in (опис or {}).items() if п in ЧИТАЧІ and к not in (None, "", U)}
    варіанти, без_коду = [], {}
    вид = умови.get("item_type")
    for з in каталог or ():
        коди = {п: ЧИТАЧІ[п][0](з) for п in умови}
        if вид and коди.get("item_type") != вид:
            continue
        бракує = [п for п, к in коди.items() if к is None]
        for п in бракує:
            без_коду[п] = без_коду.get(п, 0) + 1
        if not бракує and all(_збіг(коди[п], к, п) for п, к in умови.items()):
            варіанти.append(з)
    return варіанти, без_коду


def оцінити(варіанти, F, T, сцен=None, intent=ТИПОВИЙ_НАМІР, відмова_портрета=None):
    """{ід: вердикт} кожного варіанта — суд речі (`річ_з_фото.вердикт`) над записом каталогу, як над її річчю «хочу
    купити»."""
    import річ_з_фото as _РФ
    from колір_простір_надійність import ДЖЕРЕЛО_ФОТО_ТИПОВЕ
    вих = {}
    for з in варіанти:
        річ = dict(ід=str(з.get("id")), слот=з.get("слот"), назва=з.get("назва"), крій=з.get("крій"),
                   колір=(з.get("колір_ім") or з.get("колір_назва")), чия="хочу купити")
        вих[річ["ід"]] = _РФ.вердикт(річ, F, T, сцен, source=ДЖЕРЕЛО_ФОТО_ТИПОВЕ, intent=intent,
                                     відмова_портрета=відмова_портрета, запис=з)
    return вих


def відповідь(каталог, опис, F, T, сцен=None, intent=ТИПОВИЙ_НАМІР, відмова_портрета=None):
    """Пошук і оцінка → dict(варіанти: [{ід, назва, ціна, url, фото, slot, item_type, вердикт}] у порядку `вибір`,
    заяви: про сам пошук, choice: заяви вибору, без_коду)."""
    import суд_покупки as _СП
    варіанти, без_коду = знайти(каталог, опис)
    коди = {п: к for п, к in (опис or {}).items() if п in ЧИТАЧІ and к not in (None, "", U)}
    заяви = [_ВМ.заява("catalogue_records_without_code", field=п, count=н) for п, н in sorted(без_коду.items())]
    if not варіанти:
        return dict(варіанти=[], заяви=[_ВМ.заява("catalogue_has_none", asked=коди)] + заяви, choice=[],
                    без_коду=без_коду)
    вердикти = оцінити(варіанти, F, T, сцен, intent, відмова_портрета)
    вибір = _СП.вибір(вердикти)
    за_ід = {str(з.get("id")): з for з in варіанти}
    return dict(варіанти=[dict(ід=і, назва=за_ід[і].get("назва"), ціна=за_ід[і].get("ціна"), url=за_ід[і].get("url"),
                               фото=(list(за_ід[і].get("фото") or [])[:1]), магазин=за_ід[і].get("магазин"),
                               slot=_ВМ.код_або_невідомо("slot", за_ід[і].get("слот")),
                               item_type=(_ВМ.код("item_type", за_ід[і].get("тип")) or U), вердикт=вердикти[і])
                          for і in вибір["порядок"]],
                заяви=[_ВМ.заява("catalogue_variants_found", count=len(варіанти), asked=коди)] + заяви,
                choice=вибір["заяви"], без_коду=без_коду)


def пошук_кроками(d):
    """Генератор (`фід_розбір.ганяти`): каталог тими самими записами, що «Оціни мій образ» без пулу
    (`оцінка_образу._каталог_без_пулу_кроками`, піднімається шматками), далі пошук і суд."""
    import оцінка_образу as _ОО
    from міст_вхід import збірка_речі as _збірка_речі, нормалізувати_вхід as _нормалізувати_вхід
    кат = yield from _ОО._каталог_без_пулу_кроками(d)
    dd = _нормалізувати_вхід(dict(d))
    F, T = _збірка_речі(dd)
    return відповідь(кат, d.get("опис") or {}, F, T, intent=(dd.get("намір") or ТИПОВИЙ_НАМІР),
                     відмова_портрета=dd.get("колір_відмова"))


def пошук(вхід):
    """Ендпойнт `пошук_речі` (проби, батарея, не-Pyodide): {…вхід показу…, каталог, опис: {коди}} → JSON."""
    d = _json.loads(вхід) if isinstance(вхід, str) else (вхід or {})
    import фід_розбір as _ФР
    почато = _time.time()
    р = _ФР.ганяти(пошук_кроками(d))
    return _json.dumps(dict(р, мс=round((_time.time() - почато) * 1000)), ensure_ascii=False, default=str)


async def пошук_а(вхід):
    """`пошук` у Pyodide: між кроками каталогу — хід головному потоку сторінки (`asyncio.sleep(0)`)."""
    d = _json.loads(вхід) if isinstance(вхід, str) else (вхід or {})
    почато, г = _time.time(), пошук_кроками(d)
    try:
        while True:
            next(г)
            await _asyncio.sleep(0)
    except StopIteration as к:
        р = к.value
    return _json.dumps(dict(р, мс=round((_time.time() - почато) * 1000)), ensure_ascii=False, default=str)
