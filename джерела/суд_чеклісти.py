# «any failure is repaired BEFORE output; a failed item may not appear in a
# delivered answer». Рядок несе ЛІЧБУ й ЧАСТКУ, а не повторює механізм: у `речі`
# стоять номери пунктів, не речі образу.
# ЗНАМЕННИК — ПУНКТИ З ВХОДОМ, А НЕ ВСІ. Ділити на 16 означало б мірити образ
# бідністю фіду: на живому каталозі більшість пунктів стелі стоїть «без входу»
