# ЧОМУ ЦЕ НЕ ДУБЛЬ (Н-V15-035 забороняє два коди з одного виміру). Пункти
# чеклістів емітують СВОЇ правила (K-COL-02 про хрому, K-CRA-02 про фокус) — і
