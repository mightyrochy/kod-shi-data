def чеклісти(знахідки, E, intent="conventional", палітра=None, реєстр=None,
             аксесуари=None):
    """K-SYS-08 / K-SYS-09 / K-PAL пункт за пунктом. Повертає dict(надлишок=[…],
    прісність=[…], палітра=[…], підсумок=…). Жодного числа якості — лише стан
    кожного пункту (R-ABC-08).

    `палітра` — вихід `входи_палітри`; без нього ВСІ пункти третього списку стають
    «без входу», і це правда: без осей людини жодне правило палітри не має що
    сказати про цей образ.

    `реєстр` — вектор `реєстри.реєстр_образу`; без нього пункт 13 надлишку («жанр
    має домінанту», K-KOH-04) теж стає «без входу», і це та сама правда: жанр
    судиться з розпізнаних реєстрів, а не з поля `жанр`, якого не пише ніхто.

    `аксесуари` — вихід `accessory.входи_чекліста`; без нього те саме стається з
    четвертим списком, і теж законно: суд без аксесуарної гілки про ремінь сумки
    й щільність колготок не знає нічого."""
    за_правилом = {}
    for z in знахідки:
        if not isinstance(z, dict) or not z.get("правило"): continue
        if z.get("сила") in ("питання", "утримано"): continue
        if _під_підлогою(z.get("сила_нп")) and not z.get("блокує"): continue
        за_правилом.setdefault(z["правило"], []).append(z)
    def пункт(ід, назва, правила, вхід):
        зн = [z for r in правила for z in за_правилом.get(r, [])]
        if зн:
            стан = "провал"
        elif not правила or not _вхід_є(вхід, E, знахідки, реєстр):
            стан = "без входу"
        else:
            стан = "пройдено"
        return dict(пункт=ід, що=назва, правила=list(правила), стан=стан, вхід=вхід,
                    знахідки=[(z.get("правило"), z.get("суть")) for z in зн][:3])
    над = [пункт(*p) for p in ЧЕКЛІСТ_НАДЛИШКУ]
    Р = одна_на_річ(E)
    прс = [пункт(*p) for p in ЧЕКЛІСТ_ПРІСНОСТІ]
    _пал = палітра if isinstance(палітра, dict) else {}
    _входи_пал = {
        "вікна палітри": bool(_пал.get("вікна")),
        "≥2 кольорові речі": bool(_пал.get("вікна")) and sum(1 for e in Р if not e.get("нейтраль")) >= 2,
        "≥1 принт": bool(_пал.get("вікна")) and any(e.get("візерунок") not in (None, "", "solid", "однотон") for e in Р),
        "ахроматичне волосся": bool(_пал.get("сивина")),
        "бік температури": bool(_пал.get("бік_температури")),
        "бік b* очей": bool(_пал.get("бік_b_очей")),      # R-COL-16
    }
    def пункт_палітри(ід, назва, правила, вхід):
        зн = [z for r in правила for z in за_правилом.get(r, [])]
        стан = "провал" if зн else ("пройдено" if _входи_пал.get(вхід) else "без входу")
        return dict(пункт=ід, що=назва, правила=list(правила), стан=стан, вхід=вхід,
                    знахідки=[(z.get("правило"), z.get("суть")) for z in зн][:3])
    пал = [пункт_палітри(*p) for p in ЧЕКЛІСТ_ПАЛІТРИ]
    _входи_акс = аксесуари if isinstance(аксесуари, dict) else {}
    def пункт_аксесуара(ід, назва, правила, вхід):
        зн = [z for r in правила for z in за_правилом.get(r, [])]
        стан = "провал" if зн else ("пройдено" if _входи_акс.get(вхід) else "без входу")
        п = dict(пункт=ід, що=назва, правила=list(правила), стан=стан, вхід=вхід,
                 знахідки=[(z.get("правило"), z.get("суть")) for z in зн][:3])
        # НАЗВАНЕ ПОЛЕ ЇДЕ РАЗОМ ЗІ СТАНОМ: «без входу» без назви того, чого
        # бракує, — це та сама тиша, тільки з алібі (той самий принцип, що в
        # `accessory.БЕЗ_ВХОДУ`).
        if стан == "без входу":
            п["бракує"] = _ЯКОГО_ПОЛЯ.get(вхід, вхід)
        return п
    акс = [пункт_аксесуара(*p) for p in ЧЕКЛІСТ_АКСЕСУАРІВ]
    # B3 і B4 рахуються прямо: вони не мають правила-емітента
    гучних = [e for e in Р if not e.get("нейтраль") and lch(tuple(e["lab"]))[1] >= ІНТЕРЕС_C_МІН] if all(e.get("lab") for e in Р) else []
    for p in прс:
        if p["пункт"] == "B3":
            p["стан"] = "провал" if len(гучних) <= 1 and not any(e.get("візерунок") not in (None, "", "solid") for e in Р) else "пройдено"
            p["що"] += " (нейтралі + ≤1 акцент і жодного принту = дефолт)"
        if p["пункт"] == "B4":
            if _вхід_є("текстура", E, знахідки):
                p["стан"] = "пройдено" if len({e.get("текстура") for e in Р if e.get("текстура")}) >= 2 else "провал"
    підсумок = dict(
        надлишок={с: sum(1 for p in над if p["стан"] == с) for с in ("провал", "пройдено", "без входу")},
        прісність={с: sum(1 for p in прс if p["стан"] == с) for с in ("провал", "пройдено", "без входу")},
        палітра={с: sum(1 for p in пал if p["стан"] == с) for с in ("провал", "пройдено", "без входу")},
        аксесуари={с: sum(1 for p in акс if p["стан"] == с) for с in ("провал", "пройдено", "без входу")})
    try:
        import trace as _СЛ
        _СЛ.запис("K-SYS-08", "стеля надлишку: %(провал)d провал / %(пройдено)d пройдено / %(без входу)d без входу"
                  % підсумок["надлишок"], "чеклісти", значення=str(підсумок["надлишок"]), сила=None, напрям="чекліст")
        _СЛ.запис("K-SYS-09", "підлога прісності: %(провал)d провал / %(пройдено)d пройдено / %(без входу)d без входу"
                  % підсумок["прісність"], "чеклісти", значення=str(підсумок["прісність"]), сила=None, напрям="чекліст")
    except Exception as _e:
        import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
        if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
        pass
    try:
        import trace as _СЛ2
        _СЛ2.запис("K-PAL-01", "чекліст палітри: %(провал)d провал / %(пройдено)d пройдено / %(без входу)d без входу"
                   % підсумок["палітра"], "чеклісти", значення=str(підсумок["палітра"]), сила=None, напрям="чекліст")
    except Exception as _e:
        import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
        if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
        pass
    return dict(надлишок=над, прісність=прс, палітра=пал, аксесуари=акс, підсумок=підсумок,
                знахідки=_знахідки_чекліста(над, прс, підсумок),
                межа="«без входу» ≠ «пройдено»: пункт без поля в образі не перевірений. "
                     "Пороги пунктів 1, 6, 7, 8, 10 — фольклорні константи (тема-4 XII)")


