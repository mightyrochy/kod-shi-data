# завжди виглядала б мізерною. «Без входу» ≠ «пройдено» (K-IO-04) працює в обидва
# боки: такий пункт не зараховується ні в чисельник, ні в знаменник.
# СИЛА. Корпус FORCE для цих двох ID не оголошує — тема-4 XII дає СТРУКТУРУ й сама
# зве числа пунктів 1, 6, 7, 8, 10 фольклорними. Тому `default` («діє, поки не
# спростовано»), а не `strong`: підвищити можна лише разом із калібруванням
# порогів самих пунктів. Регістр — репліка: правило велить РЕМОНТУВАТИ до видачі,
# а не накладати вето.
_ЧЕКЛІСТ_ПРАВИЛО = {"надлишок": "K-SYS-08", "прісність": "K-SYS-09"}


def _знахідки_чекліста(над, прс, підсумок):
    """Підсумок стелі надлишку й підлоги прісності → знахідки над ОБРАЗОМ."""
    import реєстр_правил as _РЕЄСТР
    зн = []
    for бік, пункти in (("надлишок", над), ("прісність", прс)):
        п = підсумок.get(бік) or {}
        провалів = int(п.get("провал") or 0)
        if not провалів:
            continue
        з_входом = провалів + int(п.get("пройдено") or 0)
        частка = провалів / max(1, з_входом)
        назви = [str(x.get("що") or "") for x in пункти if x.get("стан") == "провал"]
        коди = [str(x.get("пункт")) for x in пункти if x.get("стан") == "провал"]
        зн.append(_РЕЄСТР._зн(
            _ЧЕКЛІСТ_ПРАВИЛО[бік], "default",
            ("стеля надлишку пробита: %d із %d перевірених пунктів провалено — %s"
             if бік == "надлишок" else
             "підлога прісності не набрана: %d із %d перевірених пунктів провалено — %s")
            % (провалів, з_входом, "; ".join(назви)[:150]),
            коди,
            ("двобічна модель якості — єдине місце, де образ судиться ЯК ЦІЛЕ, а не "
             "по одній речі: %s. Пункти без входу в знаменник не входять — «без входу» "
             "≠ «пройдено» в обидва боки (K-IO-04), тож частка міряє образ, а не бідність "
             "фіду (без входу тут %d)")
            % ("перевантаження не лікується поліпшенням окремої речі: щось мусить піти"
               if бік == "надлишок" else
               "прісність не лікується ще одним нейтральним шаром: мусить з'явитись те, "
               "чого нема", int(п.get("без входу") or 0)),
            ремонт=("тема-4 XII.1: провалений пункт РЕМОНТУЄТЬСЯ до видачі, а не "
                    "супроводжує відповідь — зняти надлишок у названих пунктах"
                    if бік == "надлишок" else
                    "тема-4 XII.2: додати джерело інтересу з меню {i1…i7} у названих "
                    "пунктах — фактура, рішення силуету, колір, деталь ремесла, хід "
                    "регістру, аксесуар як структура, жест розкладки"),
            ламається="тема-4 XII сама зве пороги пунктів 1, 6, 7, 8, 10 фольклорними "
                      "константами: СТРУКТУРА чекліста тверда, числа під нею — конвенції, "
                      "що чекають калібрування. Тому підсумок виходить `default`, а не "
                      "`strong`, і ніколи не стає вето: правило велить ремонтувати до "
                      "видачі, а не відкидати",
            вимір=частка, поріг=0.0, повна=1.0))
    return зн
