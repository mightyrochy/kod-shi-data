def входи_палітри(F, source="uncontrolled", самозвіт=None, вибір_схеми=None):
    """Які входи практикової палітри є в ЦІЄЇ людини — для `чеклісти(…, палітра=…)`.

    Рахується з `palettes.осі` і трьох вікон, а не з `палітра_практична`: потрібні
    рівно ФАКТИ НАЯВНОСТІ входу, а повна палітра будує ще й кольори, назви та
    трійки, і кликати її на кожній комбінації композитора було б дорого рівно за
    те, чого тут не питають.

    П.14 (20.09.2026): три `except Exception` тут ЗНЯТО, а не звужено. Обидві
    викликані функції тотальні на порожньому профілі — виміряно: `palettes.осі({})`
    повертає словник, `palette.бік_b_проти_людини({})` віддає `вхід=False` з власним
    `чому` («у профілі нема кольору очей»). Тобто необов'язковий вхід уже названий
    САМИМИ викликаними, і ловити тут лишалось тільки поломку. А ковталась вона в
    `{}`, від якого ВЕСЬ третій список чекліста ставав «без входу»: читач бачив
    «поля в образі нема» там, де насправді впав колірний шар. Тепер поломка летить
    у `bridge.виклик` (`помилка` + `код`), і показ показує рядок жінці.
    """
    import palettes as _ПЛ, personal_palette as _PP, colorspace as _КС
    ос = _ПЛ.осі(F or {}, source, самозвіт)
    волосся = [f for ім, f in (_PP._дані(F or {}) or {}).items() if str(ім).startswith("волосся")]
    сивина = any((f.get("C", 99) or 0) < _КС.ACHROMATIC_C for f in волосся)
    import palette as _ПАЛ
    _очі = _ПАЛ.бік_b_проти_людини(F or {}) or {}
    бік_b_очей = bool(_очі.get("вхід"))
    # «не стосується» (рядок 5281): ознаку зміряно, і її нема — волосся є й не сиве, очі є й
    # у нейтральній смузі b*. Ознаки не зміряно (волосся чи очей нема) — це «немає входу».
    не_стосується = {**({"ахроматичне волосся": "profile:сивина"} if волосся and not сивина else {}),
                     **({"бік b* очей": "profile:бік_b_очей"}
                        if _очі.get("b_очей") is not None and not бік_b_очей
                        and _очі.get("чому") != "rule_off_hand_2" else {})}
    # P8 (П-7): хто обрав схему — `вибір_палітри.для_суду` у мості; без нього (композитор, батареї)
    # суддя цього не знає, і пункт так і каже, а не зараховує вибір, якого не бачив.
    _вс = вибір_схеми if isinstance(вибір_схеми, dict) else {}
    _хто = (_вс.get("обрала") or {}).get("scheme")   # рядок 205: her | stylist | code_rank
    return dict(вікна=dict(L=_ПЛ._вікно_L(ос), C=_ПЛ._вікно_C(ос), сім_ї=_ПЛ._дуги_сімей(ос)),
                бік_температури=abs(ос["позиція"]["hue"]) >= _ПЛ._ДОМІНАНТА_МІН / 2,
                сивина=bool(сивина),
                бік_b_очей=бік_b_очей,      # R-COL-16: очі дають бік b* (не ITA шкіри)
                вибір_схеми=(_хто in ("her", "stylist")),
                м_яка=ос["позиція"]["chroma"] < 0,   # P9 (K-PAL-12): та сама вісь, що в `palettes.прийоми`
                не_стосується=не_стосується,
                бракує_вибору=(None if _хто in ("her", "stylist") else
                               [dict(_брак("scheme_choice", ("вибір_схеми",), ("stylist_choice",)),
                                     author=_хто, detail=_вс.get("бракує"),
                                     rejected=list(_вс.get("відхилено") or ()),
                                     unavailable=_вс.get("без_моделі"))]))


def _пар_вікон(знахідки):
    """Скільки носіїв мають колірне вікно в каталог від ДВОХ різних правил.

    Це і є вхід K-COL-CONF / K-COL-JOIN: тест парний, і одне вікно для нього —
    не половина відповіді, а її відсутність. Лічба тут, а не в `_вхід_є`, бо
    її треба й пробам, і §-тестам."""
    по = {}
    for z in (знахідки or []):
        if not isinstance(z, dict):
            continue
        q = z.get("запит_у_каталог") or {}
        if not any(k in _ОСІ_ЗАПИТУ for k in q):
            continue
        for ч in str(q.get("слот") or "").replace(",", "|").split("|"):
            if ч.strip():
                по.setdefault(ч.strip(), set()).add(z.get("правило"))
    return sum(1 for прав in по.values() if len(прав) >= 2)


