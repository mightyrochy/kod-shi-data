def _знахідки_чекліста(над, прс, підсумок):
    """K-SYS-08/09: вага лише за перевіреними пунктами; текст пише модель із заяв."""
    from реєстр_правил import _зн
    вих = []
    for бік, правило, пункти, код, ремонт in (
            ("надлишок", "K-SYS-08", над, "excess_ceiling_broken", "remove_excess_in_failed_points"),
            ("прісність", "K-SYS-09", прс, "blandness_floor_not_reached", "add_interest_source")):
        п = підсумок.get(бік) or {}
        провалів = int(п.get("провал") or 0)
        з_входом = провалів + int(п.get("пройдено") or 0)
        if not провалів or not з_входом:
            continue
        коди = [str(x["пункт"]) for x in пункти if x["стан"] == "провал"]
        заяви = [_ВМ.заява(код, failed=провалів, checked=з_входом)]
