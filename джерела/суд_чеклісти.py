def _провалює(z):
    """Чи знахідка провалює пункт свого правила: не питання й не утримано, вага не під підлогою
    (або блокує), не опора (ГГ-1: колона, відлуння пункт не провалюють). Одна умова на чекліст
    образу й на дочекліст живого шляху (`позначити_без_входу`)."""
    if not isinstance(z, dict) or not z.get("правило") or z.get("без_входу"):
        return False
    if z.get("сила") in ("питання", "утримано") or z.get("полярність"):
        return False
    return not (_під_підлогою(z.get("сила_нп")) and not z.get("блокує"))


def позначити_без_входу(чеклісти, записи):
    """Чекліст, у якому пункти правил із записом «без входу» стоять «без входу», а не «пройдено».

    ЧОМУ ОКРЕМО ВІД `чеклісти` (23.09.2026, рядок 141). Частину правил кольору живий
    шлях судить ПІСЛЯ `pipeline.перевірити_образ` (`суд_від_моделі.бюджет_і_відлуння`,
    `палітра_образу`): K-COL-05, K-PAL-15, K-PAL-08. Їхній запис «без входу» (колір
    речі — центр вікна слова, не вимір) до готового чекліста не доїжджав, і пункт
    правила лишався «пройдено» — рівно те мовчання, яке аудит/ПРОДУКТ.md п.4 забороняє.
    Знахідка живого шляху того самого правила (тим самим відбором, що в `чеклісти`, —
    `_провалює`) ставить пункт «провал» (рядок 2271): K-PAL-08/K-PAL-12 судить
    `палітра_образу` ПІСЛЯ `перевірити_образ`, і P4/P9 стояли «пройдено» поруч зі
    знахідкою того самого правила — звіт власника суперечив сам собі (п.4). Провал
    сильніший за «без входу»: правило, що знайшло ваду, вхід мало. Підсумок і
    знахідки K-SYS-08/09 перераховуються з нових станів: пункт «без входу» не
    входить ні в чисельник, ні в знаменник."""
    if not isinstance(чеклісти, dict):
        return чеклісти
    без, вади = {}, {}
    for z in (записи or []):
        if isinstance(z, dict) and z.get("без_входу") and z.get("правило"):
            без.setdefault(z["правило"], []).append(_брак_правила(z))
        elif _провалює(z):
            вади.setdefault(z["правило"], []).append(z)
    if not без and not вади:
        return чеклісти
    вих = dict(чеклісти)
    змінено = False
    for бік in ("надлишок", "прісність", "палітра", "аксесуари"):
        пункти = []
        for п in (чеклісти.get(бік) or []):
            зн = [z for r in ((п or {}).get("правила") or ()) for z in вади.get(r, [])]
            бр = [р for r in ((п or {}).get("правила") or ()) for р in без.get(r, []) if р]
            if isinstance(п, dict) and п.get("стан") != "провал" and зн:
                п = {к: v for к, v in п.items() if к not in ("бракує", "чому")}
                п.update(стан="провал", знахідки=list(п.get("знахідки") or [])
                         + [(z.get("правило"), z.get("суть")) for z in зн])
                змінено = True
            elif isinstance(п, dict) and п.get("стан") in ("пройдено", "без входу") and бр:
                попередні = п.get("бракує") if isinstance(п.get("бракує"), list) else []
                п = dict(п, стан="без входу", бракує=попередні + [р for р in бр if р not in попередні],
                         чому="rule_said")
                змінено = True
            пункти.append(п)
        вих[бік] = пункти
    if not змінено:
        return чеклісти
    return _перерахувати(вих)


