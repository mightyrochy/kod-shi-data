# ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after, виміряно 17.09.2026 на живому шляху).
#   before — обидва правила лишали РІВНО слід: `trace.запис` із трійкою
#            «провал / пройдено / без входу». Слід читає лог, знахідку читає
#            людина, і двобічна модель якості — єдине місце системи, яке судить
#            образ ЯК ЦІЛЕ, — не казала жінці нічого. Наряд це й тримав у
