#            над образом».
#   after  — підсумок виходить рядком вердикту.
# ЧОМУ ЦЕ НЕ ДУБЛЬ (Н-V15-035 забороняє два коди з одного виміру). Пункти
# чеклістів емітують СВОЇ правила (K-COL-02 про хрому, K-CRA-02 про фокус) — і
# кажуть, що не так із РІЧЧЮ. Тут інше твердження, якого не робить жодне з них:
# стеля образу ЯК ЦІЛОГО пробита, і тема-4 XII.1 дає з цього пряме зобов'язання —
# «any failure is repaired BEFORE output; a failed item may not appear in a
# delivered answer». Рядок несе ЛІЧБУ й ЧАСТКУ, а не повторює механізм: у `речі`
# стоять номери пунктів, не речі образу.
# ЗНАМЕННИК — ПУНКТИ З ВХОДОМ, А НЕ ВСІ. Ділити на 16 означало б мірити образ
# бідністю фіду: на живому каталозі більшість пунктів стелі стоїть «без входу»
# (довжин, металу, тканинних ярликів картка не несе), і частка провалів від 16
# завжди виглядала б мізерною. «Без входу» ≠ «пройдено» (K-IO-04) працює в обидва
# боки: такий пункт не зараховується ні в чисельник, ні в знаменник.
# СИЛА. Корпус FORCE для цих двох ID не оголошує — тема-4 XII дає СТРУКТУРУ й сама
# зве числа пунктів 1, 6, 7, 8, 10 фольклорними. Тому `default` («діє, поки не
# спростовано»), а не `strong`: підвищити можна лише разом із калібруванням
# порогів самих пунктів. Регістр — репліка: правило велить РЕМОНТУВАТИ до видачі,
# а не накладати вето.
