"""Повний опис закріпленої речі для стилістки."""
import колір_річ as _КОЛІР
import річ_з_фото as _РФ

def її_речі(речі_паспорта, без_кадрів=False):
    """Її закріплені речі з повним описом — кодами полів, без слота.

    «Речі, які отримує функціональна модель, — завжди з повним описом. Модель сама знає,
    що джинси — низ: місце речі в образі їй НЕ прописувати». `id` —
    той самий, що на картці («її-ф1»): ним перелік позначає її річ (`own`). Колір — слово
    виміру (свідок сильніший за слово моделі) і hex виміру, коли код міряв."""
    вих = []
    for р in _РФ.закріплені(речі_паспорта):
        вим = р.get("вимір") or {}
        о = {"id": _РФ.ПРЕФІКС_ІД + str(р.get("ід") or "ф?")}
        if р.get("назва"):
            о["name"] = р["назва"]
        колір = вим.get("слово") or р.get("колір")
        if колір:
            о["color"] = _РФ.код_поля("color", колір) or колір
        if _КОЛІР.hex_кольору(вим):
            о["color_hex"] = _КОЛІР.hex_кольору(вим)
        for поле, ключ in (("cut", "крій"), ("length", "довжина"), ("fabric", "матеріал"),
                           ("pattern", "принт")):
            к = _РФ.код_поля(поле, р.get(ключ))
            if к:
                о[поле] = к
        # `без_кадрів` — кадри її речей до моделі не дійшли (Е2-опора-пояснення, п.6): «photo» хибне в кожної,
        # інакше промпт казав би «also on the attached photos» про кадр, якого модель не бачила
        о["photo"] = bool(р.get("фото")) and not без_кадрів
        вих.append(о)
    return вих
