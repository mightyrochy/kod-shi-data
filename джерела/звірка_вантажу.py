# -*- coding: utf-8 -*-
"""звірка_вантажу.py — чи вантаж зібраного html відповідає поточним джерелам.

НАВІЩО (наряд Н-V35-071, джерело V35). `ВІДБИТОК_ПОКАЗУ` збирач клав у сторінку
з першого дня, і НІХТО його не звіряв: показ ніс мітку у пакеті ВХІД-V1, а
другого боку, який би її прочитав, не існувало. Тому опублікований index.html
міг місяцями рахувати кодом, старшим за джерела, — і виглядав при цьому цілком
живим. Саме це й сталось: продукт на Pages виконував код станом на 04.09, тоді
як у джерелах лежало ~35 правок, а мовчазність була повною.

ЩО ЦЕ РОБИТЬ. Для кожного зібраного html: читає назад `const ВІДБИТОК_ПОКАЗУ`
і вантаж (base64→zip), рахує відбиток ТИХ САМИХ модулів із поточних джерел і
порівнює. При розходженні друкує ГУЧНО і НАЗИВАЄ ФАЙЛИ, які розійшлися, — не
лише «щось не так». Збірки для цього не треба: секунди замість хвилин.

ЧОМУ ПОРІВНЯННЯ ПО СТРИПНУТОМУ КОДУ. Вантаж несе модулі без коментарів і
докстрінгів (`build_артефакт._стрип`), тож пряме порівняння з джерелом
червонило б на кожній комі в коментарі. Міряємо те саме, що міряє збирач, —
інакше звірка ловила б власну одиницю виміру, а не розходження версій.

Вжиток:
    python3 звірка_вантажу.py                 # усі зібрані html у корені репо
    python3 звірка_вантажу.py ../index.html   # конкретні файли
    python3 звірка_вантажу.py --детально      # друкувати й коли все збігається

Код виходу: 0 — усе збігається (і мовчить); 1 — є розходження; 2 — нема що
звіряти (жодного зібраного html) або файл не читається як збірка показу.
"""
import sys, os, re, io, base64, zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_артефакт as БА

ДЖЕРЕЛА = os.path.dirname(os.path.abspath(__file__))
КОРІНЬ = os.path.dirname(ДЖЕРЕЛА)

# `ВІДБИТОК_ПОКАЗУ` — показ; `ВІДБИТОК` — старий шаблон артефакта. Обидва тут,
# щоб звірка не мовчала на файлі лише тому, що він старшого роду.
_ВІДБ = re.compile(r'const ВІДБИТОК(?:_ПОКАЗУ)? = "([^"]*)";')
_ВАНТАЖ = re.compile(r'const МОДУЛІ(?:_ПОКАЗУ)? = "([^"]*)";')


def зібрані_html(корінь=КОРІНЬ):
    """Кожен .html у корені, який справді є збіркою (має вантаж і відбиток)."""
    знайдені = []
    for імя in sorted(os.listdir(корінь)):
        if not імя.endswith(".html"):
            continue
        шлях = os.path.join(корінь, імя)
        try:
            т = open(шлях, encoding="utf-8").read()
        except (OSError, UnicodeDecodeError):
            continue
        м = _ВАНТАЖ.search(т)
        # ШАБЛОН — НЕ ЗБІРКА. `джерела/показ.html` і його копії несуть ті самі
        # оголошення з НЕПІДСТАВЛЕНИМИ плейсхолдерами; звіряти в них нічого, і
        # ганяти на них тривогу означало б зробити звірку шумною на чистому
        # дереві — тобто такою, що її вимикають. Явно переданий шлях свою
        # діагностику все одно отримає (`звірити` нижче).
        if _ВІДБ.search(т) and м and "__" not in м.group(1) and м.group(1) != "ЗАГЛУШКА":
            знайдені.append(шлях)
    return знайдені


def звірити(шлях, джерела=ДЖЕРЕЛА):
    """→ (збігається, відбиток_у_файлі, відбиток_із_джерел, [рядки про файли]).

    `збігається is None` — файл не є збіркою показу (нічим звіряти)."""
    т = open(шлях, encoding="utf-8").read()
    м_відб, м_ван = _ВІДБ.search(т), _ВАНТАЖ.search(т)
    if not (м_відб and м_ван):
        return None, None, None, ["нема `const ВІДБИТОК…` або `const МОДУЛІ…` — "
                                  "це не збірка показу"]
    у_файлі = м_відб.group(1)
    b64 = м_ван.group(1)
    if not b64 or b64 == "ЗАГЛУШКА" or "__" in b64:
        return None, у_файлі, None, ["вантаж не підставлено (%r) — файл не зібрано"
                                     % b64[:24]]
    try:
        сирі = base64.b64decode(b64)
        with zipfile.ZipFile(io.BytesIO(сирі)) as z:
            у_вантажі = {і: z.read(і) for і in z.namelist() if і.endswith(".py")}
    except Exception as е:                      # noqa: BLE001 — причина йде в текст
        return None, у_файлі, None, ["вантаж не розпаковується: %s" % е]

    модулі = sorted(і[:-3] for і in у_вантажі)
    відсутні = [м for м in модулі if not os.path.exists(os.path.join(джерела, м + ".py"))]
    з_джерел = БА._відбиток(джерела, [м for м in модулі if м not in відсутні]) \
        if not відсутні else None

    рядки = []
    for м in модулі:
        if м in відсутні:
            рядки.append("  %-24s у вантажі є, у джерелах НЕМА" % (м + ".py"))
        elif у_вантажі[м + ".py"] != БА._стрип(os.path.join(джерела, м + ".py")):
            рядки.append("  %-24s РОЗІЙШОВСЯ з джерелом" % (м + ".py"))
    збіг = not рядки and з_джерел == у_файлі
    if not збіг:
        # Модуль, якого у вантажі НЕМА ЗОВСІМ, відбиток не бачить: він рахується
        # по тому, що запаковано. Без цього рядка «розходження є, а файлів не
        # названо» лишалось би можливим станом — рівно те, від чого звірка й
        # ставиться. Але міряємо тільки ЗАМИКАННЯ ІМПОРТІВ від `bridge`: решта
        # (audit_*, measure_*, сам збирач) у вантаж не їде за задумом, і тягати
        # її в тривогу означало б навчити читача не читати цей рядок.
        try:
            треба = БА._закриття(джерела)
        except Exception:                       # noqa: BLE001 — звірка не мусить падати
            треба = set()
        бракує = sorted(треба - set(модулі))
        if бракує:
            рядки.append("  у вантажі НЕМА %d модулів, яких вимагає замикання від "
                         "bridge: %s" % (len(бракує), ", ".join(бракує)))
    return збіг, у_файлі, з_джерел, рядки


def main(argv):
    детально = "--детально" in argv
    шляхи = [а for а in argv if not а.startswith("--")] or зібрані_html()
    if not шляхи:
        print("звірка: у %s нема жодного зібраного html — нічого звіряти" % КОРІНЬ)
        return 2
    розійшлись, нечитані = [], []
    for шлях in шляхи:
        збіг, у_файлі, з_джерел, рядки = звірити(шлях)
        імя = os.path.relpath(шлях, КОРІНЬ)
        if збіг is None:
            нечитані.append(імя)
            print("звірка: %s — %s" % (імя, рядки[0]))
            continue
        if збіг:
            if детально:
                print("звірка: %s — вантаж збігається з джерелами (відбиток %s)"
                      % (імя, у_файлі))
            continue
        розійшлись.append(імя)
        print("")
        print("!" * 78)
        print("!! ВАНТАЖ ЗАСТАРІВ: %s" % імя)
        print("!! відбиток у файлі:   %s" % у_файлі)
        print("!! відбиток з джерел:  %s" % (з_джерел or "(не рахується: у вантажі є "
                                             "модулі, яких у джерелах нема)"))
        print("!! Сторінка виконує НЕ той код, що лежить у джерелах. Перезберіть:")
        print("!!   cd джерела && python3 build_артефакт.py . ../%s показ-повний" % імя)
        print("!! Розійшлися:")
        for р in рядки:
            print("!" + р)
        print("!" * 78)
    if нечитані and not розійшлись:
        return 2
    return 1 if розійшлись else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
