"""ГЕЙТ E · ПРОГОНИ МОСТА (чисте перенесення з `gate_reach.py`, 19.09.2026).

Ярус пакета — ID, що доживають до повного результату коду ще до того, як міст
вибере, що віддати назовні (`у_пакеті`); реальні виклики `bridge.виклик` по
плану батареї × дві гілки × два наміри × три ендпойнти (`прогін`); і друга
половина петлі — код судить те, що склала модель (`прогін_від_моделі`).
Збої лічаться і стоять першим рядком звіту: доки хоч один виклик падає, решта
чисел неповна.
"""

import json

import ід_правил as ІП
from батарея_входи import БАТАРЕЯ, НАГОДИ, ДРАПИ, план_батареї
from батарея_слід import знахідки_дерева, чеклістні_дерева

def у_пакеті():
    """ID, що доживають до ПАКЕТА конвеєра — тобто до повного результату коду,
    ще до того, як міст вибере, що віддати назовні.

    ЧОМУ ЦЕЙ ЯРУС ДОДАНО ОКРЕМО. Перша версія гейта звітувала 67 «мертвих»
    правил. Перевірка одного з них (K-KOH-05) показала хибний позитив: правило
    спрацьовує й лягає в пакет, а зникає на межі `міст`, який віддає назовні
    лише вибрані поля. Тобто втрата — не в правилах, а в ОДНОМУ шарі, і без
    цього ярусу гейт звинувачував би не того.
    """
    import bridge
    зн, стат = set(), set()
    for _, риси in БАТАРЕЯ:
        for нагода, драп in [(н, д) for н in НАГОДИ for д in ДРАПИ]:
            d = dict(риси)
            d.update(зріст=168, вік=32,
                     обхвати=dict(плечі=98, груди=92, талія=72, стегна=100),
                     самозвіт=dict(метал="золото", барви="приглушені"),
                     випадок="прогін", гілка=0, намір="conventional", сценарій=нагода)
            try:
                F, T, зріст, kw = bridge._збірка(d)
                п = bridge._пакет(F, T, зріст, kw, драп=драп)
                # ── СТАТИЧНИЙ СПИСОК ОБМЕЖЕНЬ ВИРІЗАНО, І ОСЬ ЧОМУ ──────────
                # ВИМІРЯНО: `обмеження` = `статус.список()` — 31 запис, ПОБАЙТОВО
                # ІДЕНТИЧНИЙ для будь-якого профілю (звірено на двох протилежних
                # входах). У його ТЕКСТІ згадано 26 ID. Саме вони й давали
                # «доходить до ПАКЕТА: 30»: з тридцяти лише 8 залежали від
                # профілю. Тобто ярус «пакет» на 87% міряв те, що система знає
                # про власні дірки, а не те, що вона порахувала про людину.
                # Це рівно правило 1: покриття видавало себе за якість, і гейт,
                # написаний ПРОТИ цієї підміни, сам її й робив.
                п_без = {k: v for k, v in п.items() if k != "обмеження"}
                зн |= ІП.бази_в_тексті(json.dumps(п_без, ensure_ascii=False, default=str))
                стат |= ІП.бази_в_тексті(json.dumps(п.get("обмеження"),
                                                     ensure_ascii=False, default=str))
            except Exception:
                pass
    return зн, стат


def прогін():
    """Реальні виклики моста.

    Повертає (склеєний_вихід, скільки_викликів, слід, знахідки, збої).

    ── СЛІД І ЗНАХІДКА — ДВА РІЗНІ ТВЕРДЖЕННЯ (Н-P17) ─────────────────────────
    `слід` — правило назвало себе в точці спрацювання; це читає ЛОГ.
    `знахідки` — правило вийшло рядком, який бачить людина або модель; це читає
    СПОЖИВАЧ. Знахідка завжди і слід (виконалось, дійшло до виходу), тож
    `знахідки ⊆ слід`, а різниця `слід − знахідки` і є те, що проба P17
    виміряла як «31 ID, які емітуються лише записом сліду».

    ── ГЕЙТ ПЕРЕТВОРЮВАВ «ПРОДУКТ УПАВ» НА «ПРАВИЛО НЕ ДОХОДИТЬ» ───────────────
    ЩО ЦЕ МІНЯЄ (правило 3, before/after, знайдено 08.09.2026 у кроці A7).
    Виняток із `bridge.виклик` тут ловився й дописувався рядком «ЗБІЙ …» у
    `шматки`. Далі `шматки` шукались РЕГЕКСОМ НА ID ПРАВИЛ — і більше нічим:
    слово «ЗБІЙ» не рахувалось, не друкувалось і взагалі не читалось у жодному
    місці файлу (перевірено грепом: одна згадка, у цьому рядку).
      before — половина батареї йде під наміром `statement`. Поки сміливий намір
               валив `brief` і `bridge` (див. крок A5), це 16 із 32 викликів
               `запити`, і гейт звітував лише НИЖЧЕ покриття правил. Прилад,
               написаний проти підміни «покриття видає себе за якість», сам
               підміняв «продукт не працює» на «правило не доходить».
      after  — збої лічаться, і звіт починається з них: доки хоч один виклик
               моста падає, решта чисел неповна, і це сказано першим рядком.
    """
    import bridge
    import trace as СЛ
    шматки, n, сл, зн, збої = [], 0, set(), set(), []
    # `спільні` — ID, названі полем `також_правила` (спільний механізм), `чек` —
    # {ID: стани} пунктів чекліста. Обґрунтування — при `знахідки_дерева`.
    спільні, чек = set(), {}
    # ── КЛЮЧ `каталог` У БАТАРЕЇ (V02, наряд Н-00-02) ──────────────────────────
    # ЩО ЦЕ МІНЯЄ (правило 3). Коментар вище каже «половина батареї йде під
    # наміром `statement`» — і це було неправдою про ПУЛ. `bridge.запити`
    # заходить у `_пакет_каталогу` лише під `if d.get("каталог")` (bridge.py:938),
    # а батарея цього ключа не клала. Тобто 32 виклики `запити` під `statement`
    # ніколи не доходили ні до `composer.зібрати`, ні до відбору речей: сміливим
    # був лише бриф, пул не збирався взагалі. Усе, що живе за цією межею, гейт
    # чесно рахував «без сліду» — і назвати це «правило не доходить» було хибною
    # атрибуцією того самого класу, проти якого написано docstring вище.
    # ЧОМУ САМЕ `каталог_brief.xml`. Це фід, який їде В АРТЕФАКТ
    # (`build_артефакт.py: ФІД = "каталог_brief.xml"`), тобто той, на якому
    # продукт працює в людини; він же малий (427 оферів), тож батарея лишається
    # офлайновою і в межах хвилин. `каталог_повний.xml` (44 МБ) коштував би тут
    # десятки хвилин на кожен прогін гейта.
    # ЯКЩО КАТАЛОГУ НЕМА НА ДИСКУ — ключ не ставиться зовсім, і батарея працює
    # рівно як досі: мовчазний фолбек на неіснуючий файл уже коштував трьох
    # приладів (`feed.каталог_на_диску`).
    try:
        _каталог = __import__("feed").каталог_на_диску("каталог_brief.xml")
    except SystemExit:
        _каталог = None
    # ── ГІЛКА `None` У БАТАРЕЇ, А НЕ ЛИШЕ 0 (08.09.2026, крок A7) ───────────────
    # ЩО ЦЕ МІНЯЄ (правило 3). Батарея ганяла ТІЛЬКИ `гілка=0` — режим «людина
    # обрала схему». Показ за замовчуванням шле `гілка=None` («хай вирішує ші»,
    # `показ.html: ВИБІР = {гілка: null}`), і це ІНШИЙ шлях коду: пул береться
    # союзом усіх гілок розвилки, а в саму розвилку під сміливим наміром входить
    # гілка-концепт без специфікації. Саме там і лежали три падіння, знайдені в
    # кроці A5 — і гейт їх не бачив, бо цього режиму не викликав жодного разу.
    # Ціна: батарея вдвічі довша. Вона офлайнова, і це прийнятно; альтернатива —
    # прилад, який міряє конфігурацію, у якій продукт майже не працює.
    for _, риси, нагода in план_батареї():
          for гілка in (0, None):
            for намір in ("conventional", "statement"):
                # `риси` МОЖУТЬ НЕСТИ ВЛАСНІ ПОЛЯ, І ЦЕ НЕ ДЕТАЛЬ ПОРЯДКУ.
                # `update` стояв ПІСЛЯ `dict(риси)` і перебивав усе, що профіль
                # приніс, — зокрема `зріст`. Профіль «низька, 158 см» додано
                # заради смуги K-OUT-02 (нуль від 167.6 см угору), і при старому
                # порядку він мовчки ганявся на 168, тобто поза власною смугою.
                d = dict(зріст=168, вік=32,
                         обхвати=dict(плечі=98, груди=92, талія=72, стегна=100),
                         самозвіт=dict(метал="золото", барви="приглушені",
                                       нейтраль="теплі", білий="теплий"))
                d.update(риси)
                d.update(випадок="прогін гейта", намір=намір, сценарій=нагода,
                         **({} if _каталог is None else dict(каталог=_каталог)),
                         **({} if гілка is None else dict(гілка=гілка)))
                s = json.dumps(d, ensure_ascii=False)
                # `тони` і `кольори` знесено (Н-02-03): ендпойнти без викликача.
                # Батарея ходила туди, куди продукт не ходить, і піднімала цим
                # покриття — рівно та підміна, проти якої написаний цей файл.
                for ім in ("чипи", "палітри", "запити"):
                    try:
                        _вих = bridge.виклик(ім, s)
                        шматки.append(_вих)
                        n += 1
                        # ЯРУС «СЛІД» — не той самий, що «у виході». У виході ID
                        # може стояти в будь-якому вільному тексті (провенанс,
                        # застереження, нота). Слід — це запис, який правило
                        # лишило В ТОЧЦІ СПРАЦЮВАННЯ, зі значенням, на якому
                        # спрацювало. Тільки він відповідає на питання логу
                        # «яке правило дало цю різницю».
                        try:
                            _j = json.loads(_вих)
                            # ЦИТАТА ДЖЕРЕЛА — НЕ СЛІД (Н-V16-038, 12.09.2026).
                            # `palettes.прийоми` лишає ДВА записи: свій K-PAL-NN
                            # («порада») і коди, названі в полі `джерело`
                            # («цитата джерела»). Другі — провенанс поради, а не
                            # спрацювання: доти K-COL-03 діставав «ціле» ×4 від
                            # прийомів палітри, які самі нічого не судять.
                            for _з in (_j.get("слід_правил") or []):
                                if _з.get("правило") and _з.get("напрям") != СЛ.НАПРЯМ_ЦИТАТА:
                                    сл.add(_з["правило"])
                            for _р in ((_j.get("правила_рук") or {}).get("B") or []):
                                if _р.get("правило"):
                                    сл.add(_р["правило"])
                            # ЗНАХІДКА РОЗПІЗНАЄТЬСЯ ЗА ФОРМОЮ, А НЕ ЗА ВІДРОМ.
                            # Перелік відер тут уже коштував проєкту трьох
                            # загублених каналів (`знахідка.py`, чому цей файл
                            # існує). `знахідка.усі` обходить усе дерево виходу
                            # й бере те, що МАЄ форму знахідки: `правило` плюс
                            # `суть` або `чому`. Запис сліду цієї форми не має
                            # (у нього `ярлик`/`де`/`значення`), тож два яруси
                            # не змішуються.
                            _вл, _сп = знахідки_дерева(_j)
                            зн |= _вл
                            спільні |= _сп
                            for _r, _ст in чеклістні_дерева(_j).items():
                                чек.setdefault(_r, set()).update(_ст)
                        except Exception:
                            pass
                    except Exception as e:
                        збої.append(dict(виклик=ім, намір=намір,
                                         гілка=("—" if гілка is None else гілка),
                                         нагода=нагода.get("нагода"),
                                         помилка="%s: %s" % (type(e).__name__, e)))
    return dict(текст="\n".join(шматки), викликів=n, слід=сл | зн, знахідки=зн,
                спільні=спільні - зн, чекліст=чек, збої=збої)


def прогін_від_моделі(скільки_профілів=2, скільки_нагод=2):
    """ДРУГА ПОЛОВИНА ПЕТЛІ: код СУДИТЬ те, що склала модель.

    ── ЧОГО БАТАРЕЯ НЕ ТОРКАЛАСЬ ЗОВСІМ (08.09.2026, крок аудиту A9) ───────────
    ЩО ЦЕ МІНЯЄ (правило 3). `прогін` кличе пʼять ендпойнтів моста — чипи, тони,
    палітри, кольори, запити — тобто ВЕСЬ шлях ДО вибору речей. Ендпойнта
    `від_моделі`, у якому код судить складений моделлю образ, у батареї не було
    ЖОДНОГО. Правила, що живуть лише там, гейт звітував «без сліду»:
      · K-COMP-01 — координація над образами моделі (підключена 08.09, крок A5);
      · K-PAL-18 — чи вцілів акцент, якого зажадав сам код (`акцент_образу`);
      · структура образу, третій канал (`канал_3`), оголошені розриви.
    Тобто половина петлі «модель пропонує — код міряє» була для гейта невидима,
    і кожне правило звідти читалось як мертве.

    ЩО НОГА СПРАВДІ ОЖИВИЛА, А ЩО НІ (зміряно, не передбачено). Слід виріс із
    75 до 82 із 191; десять правил доходять ЛИШЕ через цей ендпойнт, K-COMP-01
    серед них. K-PAL-18 — НІ, і причина інша, ніж «батарея не кликала»: воно
    живе під `pipeline.акцент_образу`, який першим рядком виходить на порожній
    `спец_слоти`, а `bridge._пакет_каталогу` НАВМИСНО віддає порожню спеку, коли
    пул зібрано союзом схем (`гілка=None` — те, що шле показ за замовчуванням).
    Порожня спека там означає «припису не було», і це чесно. Але наслідок треба
    називати вголос: у дефолтному режимі показу перевірки виконання припису не
    існує зовсім. Записано рішенням в `аудит/A9_РІШЕННЯ.md`, не правкою тут.

    ТРИ ОБРАЗИ, А НЕ ОДИН — І ЦЕ НЕ ПРО ПОКРИТТЯ. Продукт просить у моделі N
    образів на випадок, і `bridge._вердикти_образів` при `len(набори) <= 1`
    ЧЕСНО повертає верхній вердикт і не заходить у другий прохід. Тобто з одним
    образом мовчить усе, що міряє ПОЗИЦІЮ В НАБОРІ, — насамперед K-COMP-01, чий
    набір (`набір_близькостей`) складається саме з ІНШИХ образів випадку.
    ЧОМУ САМЕ ТРИ, А НЕ ДВА (зміряно 08.09.2026): `coordination.розкид_набору`
    вимагає щонайменше трьох виміряних кандидатів — при двох рангу не існує, і
    правило чесно УТРИМУЄТЬСЯ. Батарея на двох образах діставала б «утримано» й
    так і не перевірила б головну гілку. Число тут не кругле й не вигадане: воно
    взяте з порога самого правила.

    ЦІНА НАЗВАНА: повна батарея тут коштувала б ще 32 прогони `запити` (кожен —
    прогін фіду). Береться підмножина: `скільки_профілів` × `скільки_нагод`, і
    це записано в звіті, щоб «не досягнуто» не читалось як «мертве».
    """
    import bridge, json as _js
    import trace as СЛ
    сл, зн, спільні, чек = set(), set(), set(), {}
    for _, риси in БАТАРЕЯ[:скільки_профілів]:
        for нагода in НАГОДИ[:скільки_нагод]:
            d = dict(риси)
            d.update(зріст=168, обхвати=dict(плечі=98, груди=92, талія=72, стегна=100),
                     самозвіт=dict(метал="золото", барви="приглушені"),
                     випадок="прогін гейта", намір="conventional", сценарій=нагода,
                     каталог=__import__("feed").каталог_на_диску(),
                     # `варіантів` — це СКІЛЬКИ ОБРАЗІВ ПРОСИТИ В МОДЕЛІ (міняє
                     # текст пакета й ключ кешу), а не розмір пулу. Батарея
                     # моделі не має: вона складає свої три набори з того самого
                     # пулу кандидатів сама. Два числа незалежні, і 2 тут стоїть,
                     # щоб не перебудовувати пакет ще раз заради самого тексту.
                     кеш_кольорів="кеш_кольорів.json", ліміт_фото=0, варіантів=2)
            try:
                r = _js.loads(bridge.виклик("запити", _js.dumps(d, ensure_ascii=False)))
                к = r.get("кандидати") or {}
                набори = []
                for місце in (0, 1, 2):
                    ід = [(к.get(с) or [])[місце].get("id")
                          for с in ("верх", "низ", "взуття", "сумка")
                          if len(к.get(с) or []) > місце]
                    ід = [i for i in ід if i]
                    if len(ід) >= 2:
                        набори.append(ід)
                if not набори:
                    continue
                в = _js.loads(bridge.виклик("від_моделі",
                                            _js.dumps(dict(d, ід=набори), ensure_ascii=False)))
                # ПИТАННЯ — ТЕЖ СЛІД. `bridge.від_моделі` розводить вихід на два
                # списки: виміряні знахідки і ПИТАННЯ (правило назвало себе й
                # чесно утрималось — «виміру нема», «набору не передано»). Для
                # цього гейта обидва однакові: питання доводить, що правило
                # ВИКОНАЛОСЬ і дійшло до виходу. Пропускати їх означало б
                # звітувати мертвим кожне правило, чий вхід сьогодні неповний, —
                # рівно та підміна «нема даних → вирок про код», по якій A7.
                for z in (в.get("слід_правил") or []):
                    if z.get("правило") and z.get("напрям") != СЛ.НАПРЯМ_ЦИТАТА:
                        сл.add(z["правило"])
                # Знахідки й питання — за формою, з усього дерева виходу разом
                # із вкладеними `образи`: перелік відер тут щоразу відставав від
                # коду (`знахідка.py`).
                _вл, _сп = знахідки_дерева(в)
                зн |= _вл
                спільні |= _сп
                for _r, _ст in чеклістні_дерева(в).items():
                    чек.setdefault(_r, set()).update(_ст)
            except Exception:
                continue
    return dict(слід=сл | зн, знахідки=зн, спільні=спільні - зн, чекліст=чек)
