"""Підбір речей за бажаннями й різноманітність пулу.

Бажання надходять у `паспорт.бажання_коди` полями ключів ядра. Слот і тип
звіряються з полями речі, клас «яскраві» впорядковується за хромою C*, а решта
ключів дає бал. Без кодованих бажань код підбору за бажанням не працює.

Кожен названий слот дістає `на_слот()` речей із верхівки класу; порядок серед
рівних залежить від сіда. Речі з `вже_були` поступаються рівноцінним, але не
вилучаються: за відсутності альтернативи вони лишаються законними кандидатами.
Пул не звужується — змінюється лише порядок.
"""
import random
import re
# `назва_суду` — назва, якою судиться річ: відновлена зі сторінки товару, коли
# вона є. Тут вона потрібна двічі: рядок «за бажанням додано в пул»
# має показувати те саме слово, що картка, а не рекламне речення фіду.
import фід_слот as _ФС
from семплер import сіль as _С_сіль      # лист: без проєктних імпортів
import семплер as _С
import річ_з_фото as _РФ
import внутрішня_мова as _ВМ_Б
import сценарій as _НАГОДА
import аксесуари_погода as _АП
import реєстр_правил as _Р
import колір_річ as _КР_ТИП

# акцентні аксесуари: слоти, у яких підібрані за бажанням речі дають гарантоване місце в зрізі
# (`слоти_аксесуарів`) і рядок вимоги моделі (`рядок_вимоги`)
АКЦЕНТНІ_СЛОТИ = ("шарф", "пояс", "головний_убір")


ОБРАЗІВ_НАБОРУ = 10   # скільки образів просить показ (`ОБРАЗІВ_ПЕРШОЇ_П`, показ.html)
ШИРИНА_КЛАСУ = 3      # з якої верхівки класу («найяскравіші») сід бере речі: 3 × на слот


def квота_речі(образів=ОБРАЗІВ_НАБОРУ):
    """У скількох образах набору може стояти одна річ каталогу (K-VAR-01, `частка_речі_набору`)."""
    import math
    return max(2, math.ceil(int(образів or 1) * _Р.C["частка_речі_набору"]))


def на_слот(образів=ОБРАЗІВ_НАБОРУ):
    """Скільки речей за бажанням класти в кожен названий слот, щоб квоти вистачило на весь набір."""
    import math
    return math.ceil(int(образів or 1) / квота_речі(образів))


# ── БАЖАННЯ — ПОЛЯМИ ШАРУ, А НЕ РОЗБОРОМ ФРАЗИ (Ч-4) ───────────────────────
# ЩО ТУТ БУЛО. Фразу бажання (`паспорт.бажання`) розбирав код: альтернативи («чи / або /
# кома / скісна»), заперечення («не», «без»), службові слова, стягнення родового множини
# («кепок» → «кепк»), «акценти» й «яскрав…», загальні «верх» / «низ», а слот і тип —
# класифікатором крамниць (`фід_слот.слот`) по її словах. Без шару фраза — її слова в
# переказі моделі виклику 0; з шаром — ключі ядра, склеєні в слова (`мовний_шар._фраза`).
# ЧОМУ ЗНЯТО. Її слова тлумачить лише мовна модель шару (рішення власника 24–25.09, аудит/ПРОДУКТ.md
# п.12). Шар дає бажання речами кодами, і шов кладе їх ПОЛЯМИ ключів ядра в
# `паспорт.бажання_коди` (`мовний_шар._ключі_речі`): слот, тип, колір, клас кольору, тканина,
# візерунок, довжина, ознака. Слот і тип звіряються рівністю з полями речі; «яскраве» — клас
# кольору «яскраві»; решта ключів дає бал за основою в полях речі (`_бал`). Кожна річ
# бажання — окремо (альтернативи «куртка чи жакет» перекладач дає двома речами).
# БЕЗ МОДЕЛІ ШАРУ БАЖАННЯ КОДАМИ НЕМА — «невідомо»: фраза їде моделям у «Хоче: …», а підбору
# за бажанням код не робить.
_КЛЮЧІ_БАЛУ = ("колір", "клас_кольору", "тканина", "візерунок", "довжина", "ознака")


def _основи(бажання):
    """Основи ключів бажання, що рахують бал речі: кожне слово ключа від 3 літер, коротше на
    закінчення (щонайменше 3 літери: «чорний» → «чорн», як поле `колір_назва` речі)."""
    вих = []
    for к in _КЛЮЧІ_БАЛУ:
        for w in re.findall(r"[a-zа-яіїєґ']{3,}", str((бажання or {}).get(к) or "").lower()):
            вих.append(w[:min(5, max(3, len(w) - 2))])
    return вих


def ключі_пошуку(бажання):
    """Ключі бажання без слота — рядком для `пакет_моделі.шукати_словами` (ключі ядра, не її слова)."""
    return " ".join(str(бажання[к]) for к in ("тип",) + _КЛЮЧІ_БАЛУ if (бажання or {}).get(к))


# поля, у яких шукає `пакет_моделі.шукати_словами`: бажання й пошук читають ту саму річ
# НАЗВУ БЕРЕ `_бал` ЧЕРЕЗ `назва_суду`, А НЕ ПОЛЕМ. `назва_показу` поруч із сирою лишала б хибні
# збіги, заради яких рядок і заведено: бажання «практичний» додавало в пул
# ж-00869@maxa («Комбінезон айворі») за рекламним «…додають виробу практичності»
# в реченні фіду. Рекламне речення — не назва речі, і шукати в ньому слово
# бажання означає шукати в тексті, який суд назви вже відкинув. Для 11 500 речей
# без відновленої назви `назва_суду` віддає ту саму сиру назву, що й доти.
_ПОЛЯ_СЛІВ = ("тип", "тканина", "візерунок", "колір_назва", "крій")


def _бал(r, бажання):
    """Скільки ключів бажання (їхніх основ, `_основи`) стоїть у полях речі й її назві суду."""
    текст = " ".join([_ФС.назва_для_людини(r)] + [str(r.get(к) or "") for к in _ПОЛЯ_СЛІВ]).lower()
    return sum(1 for о in _основи(бажання) if о in текст)


def _хрома(r):
    """C* виміру речі (0, коли виміру нема) — «яскравіший» для бажання класу «яскраві»."""
    lab = _КР_ТИП.точка_кольору(r) or ()
    return (float(lab[1]) ** 2 + float(lab[2]) ** 2) ** 0.5 if len(lab) >= 3 else 0.0


def _порядок(речі, сід, вже, ключ=None, відкине=None):
    """Речі в порядку сіда (або за `ключ`); ті, що вже були в її образах, і ті, які суд
    цієї погоди відкине (`відкине`), — у кінці."""
    р = list(речі)
    random.Random("%s·%s" % (сід or 0, _С_сіль("wish"))).shuffle(р)
    if ключ:
        р.sort(key=ключ)
    зайва = lambda x: (x.get("id") in вже, bool(відкине and відкине(x)))
    return sorted(р, key=зайва)


def речі_бажання(бажання, каталог, кандидати, сід=0, n=None, відсікти=None, вже=(), відкине=None):
    """dict(слоти, тип, речі) — що покласти в пул за цим бажанням; None, коли слота бажання
    нема серед кандидатів (тоді — пошук ключами, `підняти_бажання`).

    `бажання` — одна річ бажання полями ключів ядра (`паспорт.бажання_коди`, Ч-4): слот
    (і тип, коли названо) — клас речей; «яскраві» — яскравіші (C*) першими; решта ключів —
    бал (`_бал`). `n` — речей на слот (за замовчуванням `на_слот()`).

    `кандидати` — пул композитора {слот: [речі]} (речі вже в її палітрі); `відсікти`
    — `пакет_моделі.жорстке_відсічення` з температурою й вето цього прогону;
    `відкине` — свідок погоди (`вологе_вето`): такі речі йдуть останніми, щоб
    бажання не ставило першою річ, яку добір пулу й так не пропонує (замша в дощ, K-WEA-05; суд її
    з ПОГ-1 лише називає умовою)."""
    б = бажання if isinstance(бажання, dict) else {}
    вже = set(вже or ())
    ок = (lambda r: not відсікти(r)) if відсікти else (lambda r: True)
    слоти = [б["слот"]] if б.get("слот") in (кандидати or {}) else []
    if not слоти:
        return None
    тип = б.get("тип") if б.get("тип") and not str(б.get("тип")).endswith("_без_уточнення") else None
    типи = [тип] if тип else []
    # слот без типу («сукня», «верх») — увесь слот; тип — лише речі цього типу в слоті
    підходить = lambda r: r.get("слот") in слоти and (not типи or r.get("тип") in типи)
    # «яскраве …» — СПРАВЖНІЙ КЛЮЧ ДОБОРУ: яскравіші (C*) першими, решта ключів —
    # серед рівних. Без «яскравого» першими ті, що несуть більше її ключів (колір, тканину)
    яскраво = б.get("клас_кольору") == "яскраві"
    ключ = lambda r: ((-round(_хрома(r)), -_бал(r, б)) if яскраво else (-_бал(r, б), 0))
    if not слоти:
        return None
    n = int(n or на_слот())
    з_пулу = [r for с in слоти for r in (кандидати.get(с) or []) if підходить(r)]
    бачені = {r.get("id") for r in з_пулу}
    з_каталогу = [r for r in (каталог or []) if r.get("id") not in бачені and підходить(r) and ок(r)]
    # ── КЛАС, А НЕ ОДНА РІЧ ─────────────────────────
    # Доти ключ сортував СТРОГО: «яскрав…» — за хромою до одиниці, тож сід міняв
    # лише рівні, а рівних за хромою нема — «Червона коротка куртка» стояла першою
    # на кожному сіді й у кожному сценарії. Тепер ключ ділить клас на ТИРИ: для
    # яскравості — верхівка `ШИРИНА_КЛАСУ × n` найяскравіших слота проти решти; для її
    # ключів — бал (дискретний, «біла сукня» — білі першими, як доти).
    # Усередині тиру порядок дає сід (`_порядок`): клас той самий, речі різні.
    if яскраво:
        верхівка = set()
        for с in слоти:
            у_слоті = sorted((r for r in з_пулу + з_каталогу if r.get("слот") == с), key=lambda r: -_хрома(r))
            верхівка |= {r.get("id") for r in у_слоті[:ШИРИНА_КЛАСУ * n]}
        тир = lambda r: ((r.get("id") not in верхівка), -_бал(r, б))
    else:
        тир = ключ
    # її бажання сильніше за порядок палітри (аудит/ПРОДУКТ.md п.9): річ, що несе більше її ключів,
    # стоїть першою, звідки б не прийшла; серед рівних — спершу пул, потім каталог
    усі = sorted(_порядок(з_пулу, сід, вже, тир, відкине) + _порядок(з_каталогу, сід, вже, тир, відкине),
                 key=lambda x: (bool(відкине and відкине(x)), x.get("id") in вже, тир(x)))
    # n НА СЛОТ: кожна річ бажання має власний слот і власне n
    по_слотах = [[r for r in усі if r.get("слот") == с][:n] for с in слоти]
    речі = [рч[i] for i in range(n) for рч in по_слотах if i < len(рч)][:2 * n]
    # скільки речей, що вже були в її образах, цей підбір оминув — тиск названий числом
    оминуто = sum(1 for r in з_пулу + з_каталогу if r.get("id") in вже) - sum(1 for r in речі if r.get("id") in вже)
    return dict(слоти=слоти, тип=тип, речі=речі, оминуто_вже_були=оминуто)


# великі слоти образу — ті самі, що в суді схеми (`суд_від_моделі._ВЕЛИКІ_СЛОТИ`)
ВЕЛИКІ_СЛОТИ = ("верх", "низ", "сукня", "комплект", "верхній_шар")


def _колір_у_великі(б, каталог, кандидати, її_слоти, сід=0, відсікти=None, вже=(), відкине=None):
    """dict(слоти, тип, речі) — речі названого нею кольору у ВЕЛИКИХ слотах пулу; None, коли таких нема.

    ЇЇ-ВИБІР: колір відкриває кожен великий слот так само, як бажання зі слотом
    (`речі_бажання`): річ, чия назва чи поле кольору несе цей колір, — у пул і тримається зрізом.
    Доречність речі для нагоди судить суд, не пул (аудит/ПРОДУКТ.md п.17)."""
    лише_колір = {"колір": б.get("колір")}
    речі, слоти = [], []
    for с in ВЕЛИКІ_СЛОТИ:
        if с not in (кандидати or {}) or с in її_слоти:
            continue
        з = речі_бажання(dict(б, слот=с), каталог, кандидати, сід=сід, відсікти=відсікти, вже=вже,
                         відкине=відкине)
        свої = [r for r in ((з or {}).get("речі") or []) if _бал(r, лише_колір) > 0]
        if свої:
            слоти.append(с)
            речі += свої
    return dict(слоти=слоти, тип=None, речі=речі, оминуто_вже_були=None) if речі else None


def підняти_бажання(PL, каталог, кандидати, паспорт, сцен, вже_були=None, тримати=False, вето=None,
                    не_ця=None):
    """Покласти в пул першими речі за бажаннями паспорта (до шести фраз); `кандидати` міняються на місці.

    Бажання — речі полями ключів ядра (`паспорт.бажання_коди`, Ч-4; без моделі шару їх нема).
    Річ бажання зі слотом — `речі_бажання` (слот і тип, решта ключів, сід, `вже_були` у кінці,
    погода); знайдене тримається зрізом (`семплер.ПОЛЕ_УТРИМАННЯ`). Колір без слота й типу —
    той самий підбір у кожному великому слоті (`_колір_у_великі`). Решта без слота —
    `PL.шукати_словами` ключами (`ключі_пошуку`): знайдене стає першим, лише коли його ще нема
    в слоті, а зрізом тримається, лише коли `тримати` (траурна нагода).
    `вето` — чинний перелік (`pipeline.вето_чинне`), той самий, що в доборі
    й на екрані: її прохання не стає забороною і в підборі за бажанням. Річ із каталогу
    проходить ті самі відсічення, що пул (`відсікти_пул`): температура, вето, ошатність,
    замша за сильної непогоди (ВІДСІВ-1; у звичайний дощ вона лише йде останньою — `вологе_вето`)
    і `не_ця` — відхилена нею річ за бажанням не вертається.
    Повертає dict(за_бажанням, її_вибір, слоти_аксесуарів, вимога, звіт); назва в
    `за_бажанням` — без стелі: вона їде у звіт власника."""
    опади = сцен.get("опади") or паспорт.get("опади")
    _темп = сцен.get("темп_c") if сцен.get("темп_c") is not None else паспорт.get("темп_c")
    _не_ця = {str(x) for x in (не_ця or ()) if str(x or "").strip()}
    ошатність = сцен.get("_ошатність") or паспорт.get("ошатність")
    відсікти = lambda r: (str(r.get("id") or "") in _не_ця
                          or PL._жорстке_відсічення(r, сцен.get("темп_c"), вето, ошатність,
                                                     PL.непогода_пулу(сцен, паспорт)))
    слова = {_С.ПОЛЕ_УТРИМАННЯ: True} if тримати else {}
    за_бажанням, її_вибір, знайдено = [], set(), []
    # ЇЇ РІЧ ЗАКРИВАЄ БАЖАННЯ (доповнення 207, живий прогін власника 24.09): «спідниця»
    # при її власній міні-спідниці з фото тягла в пул п'ять ЧУЖИХ спідниць — конкурентів
    # речі, яка й так стоїть у кожному образі. Фраза, усі слоти якої займає її закріплена
    # річ (`річ_з_фото.займає`), нічого не підбирає й названа у звіті `закрито_її_річчю`.
    її_слоти = set().union(*[_РФ.займає(р["слот"]) for р in _РФ.закріплені(паспорт.get("речі_з_фото"))])
    закрито = []
    коди = {}
    for б in [x for x in (паспорт.get("бажання_коди") or []) if isinstance(x, dict)][:6]:
        фраза = str(б.get("фраза") or ключі_пошуку(б))
        # стилістці — кодами (`for_her_wish`); фраза лишається звіту власника
        коди[фраза] = _ВМ_Б.бажання_кодом(б) or фраза
        if б.get("слот") and б["слот"] in її_слоти:
            закрито.append(фраза)
            continue
        з = речі_бажання(б, каталог, кандидати, сід=int(сцен.get("сід") or 0), відсікти=відсікти,
                         вже=вже_були,
                         # її бажання САМЕ замші (тканина бажання кодом) — не «відкине»: вона попросила
                         відкине=(None if PL.бажання_вологочутливого(б) else вологе_вето(опади, _темп)))
        if з is None and б.get("колір") and not б.get("тип"):
            з = _колір_у_великі(б, каталог, кандидати, її_слоти, сід=int(сцен.get("сід") or 0),
                                відсікти=відсікти, вже=вже_були,
                                відкине=(None if PL.бажання_вологочутливого(б) else вологе_вето(опади, _темп)))
        знайдено.append((фраза, з))
        if з is None:
            if not ключі_пошуку(б):
                continue
            for r in PL.шукати_словами(каталог, ключі_пошуку(б), n=4, темп_c=сцен.get("темп_c"), вето=вето,
                                       сід=int(сцен.get("сід") or 0)):
                сл = r.get("слот")
                if сл in кандидати and сл not in її_слоти and all(x.get("id") != r.get("id") for x in кандидати[сл]):
                    кандидати[сл].insert(0, dict(r, за_бажанням=коди[фраза], **слова))
                    за_бажанням.append(dict(id=r.get("id"), назва=_ФС.назва_для_людини(r), бажання=фраза, слот=сл))
                    її_вибір.add(r.get("id"))
            continue
        for r in reversed(з["речі"]):
            сл = r.get("слот")
            кандидати[сл] = [x for x in кандидати[сл] if x.get("id") != r.get("id")]
            кандидати[сл].insert(0, dict(r, за_бажанням=коди[фраза], **{_С.ПОЛЕ_УТРИМАННЯ: True}))
        її_вибір.update(r.get("id") for r in з["речі"])
        за_бажанням += [dict(id=r.get("id"), назва=_ФС.назва_для_людини(r), бажання=фраза,
                             слот=r.get("слот")) for r in з["речі"]]
    звіт = dict(бажання=[dict(фраза=ф, слоти=(з or {}).get("слоти"), тип=(з or {}).get("тип"),
                              знайдено=(len(з["речі"]) if з else None),
                              оминуто_вже_були=((з or {}).get("оминуто_вже_були") or None),
                              як=("слотом і типом" if з else "ключами (бажання без слота)"))
                         for ф, з in знайдено],
                **({"закрито_її_річчю": закрито} if закрито else {}))
    # СЛОТ НАЗИВАЄТЬСЯ ЗА РЕЧАМИ, А НЕ ЗА ФРАЗОЮ: місце в
    # зрізі гарантується тому слоту, у якому річ СТОЇТЬ, а не тому, який фраза
    # згадала. «Ремінців, шарфів чи кепок» називає три слоти, а чотири речі підбору
    # можуть лягти у два — і третьому гарантувалося б місце під річ, якої нема.
    акс = tuple(dict.fromkeys(r.get("слот") for _, з in знайдено if з
                              for r in з["речі"] if r.get("слот") in АКЦЕНТНІ_СЛОТИ))
    return dict(за_бажанням=за_бажанням, її_вибір=її_вибір, слоти_аксесуарів=акс,
                вимога=рядок_вимоги(знайдено, вже_були=bool(вже_були)),
                вимога_заява=заява_вимоги(знайдено, вже_були=bool(вже_були), коди=коди), звіт=звіт)


def вологе_вето(опади, темп_c=None):
    """Предикат «на річ у цю погоду суд ставить умову» (замша, нубук, велюр; K-WEA-05) — або None, коли опади не мокрі.

    З ВІДСІВ-1 (02.10) це РАНГ, а не відсів: такі речі йдуть після решти (`речі_бажання`,
    `міст_відповіді` — пара на заміну); знімає їх із пулу лише сильна непогода
    (`пакет_моделі.непогода_пулу`).
    Те саме читання, що в `суд_погода.погода` (з ПОГ-1 суд не блокує, а називає умову): слово матеріалу
    `аксесуари_погода.відмовляє_у_волозі` (картка → волокно → склад) або слово руки
    «незахищена_шкіра»."""
    if _НАГОДА.канон_опади(опади, темп_c) not in _НАГОДА.МОКРІ_ОПАДИ:
        return None
    return lambda r: bool(_АП.відмовляє_у_волозі(r) or "незахищена_шкіра" in _АП.матеріал_у_волозі(r))


def посунути_вже_були(кандидати, вже):
    """(кандидати, звіт): речі з `вже` у кінці свого слота з позначкою `вже_був`.

    Звіт — {посунуто: {слот: n}, без_альтернативи: [слоти, де ВСІ речі вже були]}:
    тиск різноманітності названий і там, де поступитись нема кому."""
    вже = set(вже or ())
    if not вже:
        return кандидати, None
    вих, посунуто, без_альт = {}, {}, []
    for с, рч in (кандидати or {}).items():
        так = [dict(r, вже_був=True) for r in рч if r.get("id") in вже]
        ні = [r for r in рч if r.get("id") not in вже]
        вих[с] = ні + так
        if так:
            посунуто[с] = len(так)
            if not ні:
                без_альт.append(с)
    return вих, dict(вже_були=len(вже), посунуто=посунуто, без_альтернативи=sorted(без_альт))


def рядок_вимоги(знайдено, вже_були=False):
    """Рядок у `правила` пакета: що вона просила з аксесуарів і що робити з речами, що вже були."""
    рядки = []
    # СЛОТИ РЯДКА — ТІ, У ЯКИХ РІЧ СПРАВДІ СТОЇТЬ. Рядок
    # обіцяє моделі «у пулі такі речі стоять першими», тож називати він має слоти
    # ПІДІБРАНИХ речей, а не всі, що згадала фраза: на `main` «хочеться більше
    # ремінців, шарфів чи кепок» називала «пояс» і «шарф», а шарфів підбір не давав
    # жодного — обіцянка без речей за нею.
    акс = [(ф, [r for r in з["речі"] if r.get("слот") in АКЦЕНТНІ_СЛОТИ])
           for ф, з in знайдено if з and з["речі"]]
    акс = [(ф, рч) for ф, рч in акс if рч]
    if акс:
        рядки.append("Вона просила: %s. Покладай у кожен образ, де це доречно, річ зі слота %s — "
                     "у пулі такі речі стоять першими й несуть поле «за_бажанням»."
                     % ("; ".join("«%s»" % ф for ф, _ in акс),
                        ", ".join("«%s»" % с for с in dict.fromkeys(
                            r.get("слот") for _, рч in акс for r in рч))))
    # КВОТА ЧИСЛОМ: рядок каже, що бажання — клас, і скільки разів можна одну річ
    з_речами = [з for _, з in знайдено if з and з["речі"]]
    if з_речами:
        рядки.append("Бажання — це клас речей, а не одна річ: одну річ «за_бажанням» бери щонайбільше "
                     "в %d образах набору, решту — іншими речами того ж класу (K-VAR-01); її власна "
                     "річ — не повтор." % квота_речі())
    if вже_були:
        рядки.append("Речі з полем «вже_був» стояли в її образах попереднього збору цього сценарію. "
                     "Бери таку лише тоді, коли іншої речі того самого слота, що підходить, у пулі нема: "
                     "вона просила різноманітності.")
    return " ".join(рядки) or None


def заява_вимоги(знайдено, вже_були=False, коди=None):
    """Той самий рядок `рядок_вимоги` внутрішньою мовою (ВМ-1, аудит/ПРОДУКТ.md п.12): бажання — кодами
    (`коди`: фраза → `внутрішня_мова.бажання_кодом`), слоти — кодами, квота — числом. Порожньо — None."""
    з = []
    акс = [(ф, [r for r in зн["речі"] if r.get("слот") in АКЦЕНТНІ_СЛОТИ])
           for ф, зн in знайдено if зн and зн["речі"]]
    акс = [(ф, рч) for ф, рч in акс if рч]
    if акс:
        з.append(_ВМ_Б.заява("wish_kinds_first", wishes=[(коди or {}).get(ф) or _ВМ_Б.вільний(ф) for ф, _ in акс],
                           kinds=[_ВМ_Б.код_або_невідомо("slot", с) for с in dict.fromkeys(
                               r.get("слот") for _, рч in акс for r in рч)]))
    if any(зн and зн["речі"] for _, зн in знайдено):
        з.append(_ВМ_Б.заява("wish_is_a_class", max_outfits=квота_речі()))
    if вже_були:
        з.append(_ВМ_Б.заява("shown_before_last_resort"))
    return з or None
