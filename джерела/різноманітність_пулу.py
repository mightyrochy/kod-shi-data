import random
import re

# акцентні аксесуари, на які вказує слово «акценти» без назви слота
АКЦЕНТНІ_СЛОТИ = ("шарф", "пояс", "головний_убір")
_АКЦЕНТ = re.compile(r"акцент")


# ── ВСТАВНИЙ ГОЛОСНИЙ РОДОВОГО МНОЖИНИ (24.09.2026, рядок 198) ──────────────
# Ключі `фід_слот.СЛОТ_КЛЮЧІ` — це основи НАЗИВНОГО: «кепк», «шапк», «хустк»,
# «сумк», «балетк». У родовому множини між двома приголосними основи стає
# голосний — «кепка → кепок», «шапка → шапок», «хустка → хусток», — і жодне
# скорочення основи туди не дістане: літери розсунуто. Жінка ж просить саме в
# цій формі: у файлі вердиктів тестувальниці «Ір» стоїть «хочеться більше
# ремінців, шарфів чи КЕПОК», і на `main` ця фраза давала слоти «пояс» і «шарф»,
# а головного убору не давала зовсім.
# Стягнення застосовується ЛИШЕ як другий захід — коли класифікатор на сирій
# фразі не знайшов нічого: інакше воно правило б слова, які й так упізнані.
_ВСТАВНИЙ = re.compile(r"([бвгґджзклмнпрстфхцчшщ])[ое]к(?![а-яіїєґ'’])")


def _стягнути(фраза):
    """«кепок» → «кепк», «шапок» → «шапк», «хусток» → «хустк», «носок» → «носк»."""
    return _ВСТАВНИЙ.sub(r"\1к", str(фраза or ""))


def слот_бажання(фраза):
    """(слот, тип) речі, яку називає фраза бажання, — або (None, None).

    Той самий класифікатор, яким розкладено каталог (`фід_слот.слот`, `тип_речі`):
    бажання й річ говорять одним словником, другого переліку тут не заводиться.
    Другим заходом — та сама фраза без вставного голосного родового множини
    (`_стягнути`): словник слотів тут НЕ чіпається, бо він розкладає ще й каталог."""
    import фід_слот as _ФС
    for текст in (str(фраза or ""), _стягнути(фраза)):
        o = {"назва": текст, "категорія": "", "параметри": {}}
        сл = _ФС.слот(o)
        if сл:
            т = _ФС.тип_речі(o, сл)
            return сл, (т if т and not str(т).endswith("_без_уточнення") else None)
    return None, None


# АЛЬТЕРНАТИВИ Й ЗАПЕРЕЧЕННЯ (рядок 180). «куртку чи жакет», «джинси / штани»,
# «пальто або тренч» — кілька речей одного бажання; класифікатор читає ОДНУ назву, тож
# фраза ділиться на частини, і кожна читається ним окремо. «не темний», «без чорного»,
# «але не чорна» — слово, від якого вона відмовилась: воно не додає балу, а віднімає.
_АЛЬТ = re.compile(r"\s*(?:,|/|;|\bчи\b|\bабо\b)\s*")
_ЗАПЕРЕЧЕННЯ = ("не", "без")
_СЛУЖБОВІ = ("але", "або", "чи", "та", "щось", "хочу") + _ЗАПЕРЕЧЕННЯ


def частини_бажання(фраза):
    """[(слот, тип)] кожної частини фрази, розділеної «чи / або / кома / скісна», —
    без повторів, у порядку фрази; частини, що речі не називають, випадають."""
    пари = []
    for ч in _АЛЬТ.split(str(фраза or "")):
        п = слот_бажання(ч) if ч.strip() else (None, None)
        if п[0] and п not in пари:
            пари.append(п)
    return пари


def _слова(фраза):
    """[(основа, заперечено)] слів фрази: службові випадають; слово одразу після «не» /
    «без» — заперечене, і його основа коротша (щонайменше 3 літери: «чорна», «чорного»
    → «чор…» поля «чорний»)."""
    слова, заперечено = [], False
    for w in re.findall(r"[a-zа-яіїєґ0-9']+", str(фраза or "").lower()):
        if w in _ЗАПЕРЕЧЕННЯ:
            заперечено = True
            continue
        if len(w) >= 3 and w not in _СЛУЖБОВІ:
            слова.append((w[:min(4, max(3, len(w) - 3))] if заперечено else w[:min(5, max(3, len(w) - 2))],
                          заперечено))
        заперечено = False
    return слова


# поля, у яких шукає `пакет_моделі.шукати_словами`: бажання й пошук читають ту саму річ
_ПОЛЯ_СЛІВ = ("назва", "тип", "тканина", "візерунок", "колір_назва", "крій")
_ЯСКРАВО = re.compile(r"яскрав")


def _бал(r, фраза):
    """Скільки слів фрази є в полях речі, мінус заперечені («не чорна» — мінус чорним).
    Основа коротша на закінчення (щонайменше 3 літери): «біла» / «чорні» — це
    «білий» / «чорний» поля `колір_назва`."""
    текст = " ".join(str(r.get(к) or "") for к in _ПОЛЯ_СЛІВ).lower()
    return sum((-1 if ні else 1) for о, ні in _слова(фраза) if о in текст)


def _хрома(r):
    """C* виміру речі (0, коли виміру нема) — «яскравіший» для слова «акценти»."""
    lab = r.get("lab") or ()
    return (float(lab[1]) ** 2 + float(lab[2]) ** 2) ** 0.5 if len(lab) >= 3 else 0.0


def _порядок(речі, сід, вже, ключ=None, відкине=None):
    """Речі в порядку сіда (або за `ключ`); ті, що вже були в її образах, і ті, які суд
    цієї погоди відкине (`відкине`), — у кінці."""
    р = list(речі)
    random.Random("%s·бажання" % (сід or 0)).shuffle(р)
    if ключ:
        р.sort(key=ключ)
    зайва = lambda x: (x.get("id") in вже, bool(відкине and відкине(x)))
    return sorted(р, key=зайва)


def речі_бажання(фраза, каталог, кандидати, сід=0, n=4, відсікти=None, вже=(), відкине=None, рука1=()):
    """dict(слоти, тип, речі) — що покласти в пул за цим бажанням; None, коли фраза речі не називає.

    `кандидати` — пул композитора {слот: [речі]} (речі вже в її палітрі); `відсікти`
    — `пакет_моделі._жорстке_відсічення` з температурою й вето цього прогону;
    `відкине` — свідок суду цієї погоди (`вологе_вето`): такі речі йдуть останніми, щоб
    бажання не ставило першою річ, яку суд потім заблокує (замша в дощ, K-WEA-01);
    `рука1` — id, що стоять першими в слотах руки 1 цього збору: у руці 2 вони йдуть
    після свіжих, інакше обидві руки брали б ті самі кілька речей її палітри."""
    вже, рука1 = set(вже or ()), set(рука1 or ())
    ок = (lambda r: not відсікти(r)) if відсікти else (lambda r: True)
    акцент = bool(_АКЦЕНТ.search(str(фраза or "").lower()))
    if акцент:
        слоти, тип = [с for с in АКЦЕНТНІ_СЛОТИ if с in кандидати], None
        підходить = lambda r: r.get("слот") in слоти
        ключ = lambda r: -_хрома(r)
    else:
        пари = [(с, т) for с, т in частини_бажання(фраза) if с in кандидати]
        if not пари:
            return None
        # КІЛЬКА РЕЧЕЙ ОДНОГО БАЖАННЯ (рядок 180): тип, названий будь-якою частиною,
        # шукається в усіх слотах, які називає фраза — «куртка чи жакет»: куртки й
        # блейзери і верхнього шару, і верху; частина без типу («сукня») — свій слот
        # за основою слова в назві, як доти
        слоти = list(dict.fromkeys(с for с, _ in пари))
        типи = list(dict.fromkeys(т for _, т in пари if т))
        тип = " / ".join(типи) or None
        # ── ОСНОВА, А НЕ ПЕРШІ П'ЯТЬ ЛІТЕР (24.09.2026, рядок 198) ────────────
        # Тут стояло `_основи` — перші 5 літер слова, як у `шукати_словами`. Для
        # НАЗИВНОГО це основа й є («шарф»), а для будь-якої іншої форми — ні:
        # «шарфів» давало «шарфі», і жоден із 48 шарфів каталогу, чия назва
        # починається зі «Шарф», під цю основу не підпадав. Слот при цьому
        # знаходився — тобто код казав моделі «Вона просила шарф, у пулі такі речі
        # стоять першими», а в пулі не стояло жодного. Тим самим `_слова`, яким уже
        # рахується `_бал`, основа коротшає на закінчення; заперечені слова («не
        # чорна») у фільтр назви не йдуть — вони віднімають бал, а не добирають річ.
        без_типу = {с: [о for о, ні in _слова(ч) if not ні] for ч in _АЛЬТ.split(str(фраза))
                    for с, т in [слот_бажання(ч)] if с and not т}
        підходить = lambda r: ((r.get("слот") in слоти and r.get("тип") in типи)
                               or any(о in str(r.get("назва") or "").lower() for о in без_типу.get(r.get("слот"), ())))
        # «яскравий …» — СПРАВЖНІЙ КЛЮЧ ДОБОРУ (рядок 180): яскравіші (C*) першими, решта
        # її слів — серед рівних. Без «яскрав…» першими ті, що несуть більше її слів
        # (колір, тканину), мінус заперечені: «біла сукня» — білі, «не чорна» — не чорні
        яскраво = bool(_ЯСКРАВО.search(str(фраза).lower()))
        ключ = lambda r: ((-round(_хрома(r)), -_бал(r, фраза)) if яскраво else (-_бал(r, фраза), 0))
    if not слоти:
        return None
    з_пулу = [r for с in слоти for r in (кандидати.get(с) or []) if підходить(r)]
    бачені = {r.get("id") for r in з_пулу}
    з_каталогу = [r for r in (каталог or []) if r.get("id") not in бачені and підходить(r) and ок(r)]
    # її слова сильніші за порядок палітри (CLAUDE.md п.9): річ, що несе більше її слів,
    # стоїть першою, звідки б не прийшла; серед рівних — спершу пул, потім каталог
    бал = (lambda x: 0) if акцент else ключ   # акценти — як доти: хрома лише в межах пулу й каталогу
    речі = sorted(_порядок(з_пулу, сід, вже, ключ, відкине) + _порядок(з_каталогу, сід, вже, ключ, відкине),
                  key=lambda x: (bool(відкине and відкине(x)), x.get("id") in вже, x.get("id") in рука1,
                                 бал(x)))[:n]
    # скільки речей, що вже були в її образах, цей підбір оминув — тиск названий числом
    оминуто = sum(1 for r in з_пулу + з_каталогу if r.get("id") in вже) - sum(1 for r in речі if r.get("id") in вже)
    return dict(слоти=слоти, тип=тип, речі=речі, оминуто_вже_були=оминуто)


def підняти_бажання(PL, каталог, кандидати, паспорт, сцен, вже_були=None, тримати=False, розвести_з=None, вето=None,
                    не_ця=None):
    """Покласти в пул першими речі за бажаннями паспорта (до шести фраз); `кандидати` міняються на місці.

    Фраза, що називає річ, — `речі_бажання` (слот і тип, решта її слів, сід, `вже_були`
    у кінці, погода); знайдене тримається зрізом (`семплер.ПОЛЕ_УТРИМАННЯ`). Фраза без
    слота — `PL.шукати_словами`, як доти: знайдене стає першим, лише коли його ще нема
    в слоті, а зрізом тримається, лише коли `тримати` (траурна нагода, рядок 154).
    `розвести_з` — пул руки 1 цього збору (для руки 2): її перші речі слота йдуть після свіжих.
    `вето` — чинний перелік (`pipeline.вето_чинне`, рядок 156), той самий, що в доборі
    й на екрані: її прохання не стає забороною і в підборі за бажанням. Річ із каталогу
    проходить ті самі відсічення, що пул (`відсікти_пул`): температура, вето, ошатність,
    замша в дощ (рядок 161) і `не_ця` — відхилена нею річ за бажанням не вертається.
    Повертає dict(за_бажанням, її_вибір, слоти_аксесуарів, вимога, звіт); назва в
    `за_бажанням` — без стелі: вона їде у звіт власника (рядок 165)."""
    import семплер as _С
    опади = сцен.get("опади") or паспорт.get("опади")
    _не_ця = {str(x) for x in (не_ця or ()) if str(x or "").strip()}
    ошатність = сцен.get("_ошатність") or паспорт.get("ошатність")
    відсікти = lambda r: (str(r.get("id") or "") in _не_ця
                          or PL._жорстке_відсічення(r, сцен.get("темп_c"), вето, ошатність, сцен.get("опади")))
    слова = {_С.ПОЛЕ_УТРИМАННЯ: True} if тримати else {}
    за_бажанням, її_вибір, знайдено = [], set(), []
    рука1 = {i for рч in (розвести_з or {}).values() for i in рч[:ГОЛОВА_РУК + 1]}
    for фраза in (паспорт.get("бажання") or [])[:6]:
        з = речі_бажання(фраза, каталог, кандидати, сід=int(сцен.get("сід") or 0), відсікти=відсікти,
                         вже=вже_були, відкине=вологе_вето(опади), рука1=рука1)
        знайдено.append((фраза, з))
        if з is None:
            for r in PL.шукати_словами(каталог, фраза, n=4, темп_c=сцен.get("темп_c"), вето=вето):
                сл = r.get("слот")
                if сл in кандидати and all(x.get("id") != r.get("id") for x in кандидати[сл]):
                    кандидати[сл].insert(0, dict(r, за_бажанням=фраза, **слова))
                    за_бажанням.append(dict(id=r.get("id"), назва=str(r.get("назва") or ""), бажання=фраза, слот=сл))
                    її_вибір.add(r.get("id"))
            continue
        for r in reversed(з["речі"]):
            сл = r.get("слот")
            кандидати[сл] = [x for x in кандидати[сл] if x.get("id") != r.get("id")]
            кандидати[сл].insert(0, dict(r, за_бажанням=фраза, **{_С.ПОЛЕ_УТРИМАННЯ: True}))
        її_вибір.update(r.get("id") for r in з["речі"])
        за_бажанням += [dict(id=r.get("id"), назва=str(r.get("назва") or ""), бажання=фраза,
                             слот=r.get("слот")) for r in з["речі"]]
    звіт = dict(бажання=[dict(фраза=ф, слоти=(з or {}).get("слоти"), тип=(з or {}).get("тип"),
                              знайдено=(len(з["речі"]) if з else None),
                              оминуто_вже_були=((з or {}).get("оминуто_вже_були") or None),
                              як=("слотом і типом" if з else "словами (фраза не називає речі)"))
                         for ф, з in знайдено])
    # СЛОТ НАЗИВАЄТЬСЯ ЗА РЕЧАМИ, А НЕ ЗА ФРАЗОЮ (24.09.2026, рядок 198): місце в
    # зрізі гарантується тому слоту, у якому річ СТОЇТЬ, а не тому, який фраза
    # згадала. «Ремінців, шарфів чи кепок» називає три слоти, а чотири речі підбору
    # можуть лягти у два — і третьому гарантувалося б місце під річ, якої нема.
    акс = tuple(dict.fromkeys(r.get("слот") for _, з in знайдено if з
                              for r in з["речі"] if r.get("слот") in АКЦЕНТНІ_СЛОТИ))
    return dict(за_бажанням=за_бажанням, її_вибір=її_вибір, слоти_аксесуарів=акс,
                вимога=рядок_вимоги(знайдено, вже_були=bool(вже_були)), звіт=звіт)


def вологе_вето(опади):
    """Предикат «суд K-WEA-01 цієї погоди заблокує річ» — або None, коли опади не мокрі.

    Те саме читання, що в `суд_погода.погода` (рядок 161): слово матеріалу
    `аксесуари_погода.відмовляє_у_волозі` (картка → волокно → склад) або слово руки
    «незахищена_шкіра»."""
    import сценарій as _НАГОДА, аксесуари_погода as _АП
    if _НАГОДА.канон_опади(опади) not in _НАГОДА.МОКРІ_ОПАДИ:
        return None
    return lambda r: bool(_АП.відмовляє_у_волозі(r) or "незахищена_шкіра" in _АП.матеріал_у_волозі(r))


ГОЛОВА_РУК = 3   # скільки перших речей слота руки 1 не стоїть на перших місцях руки 2


def розвести_голови(кандидати, розвести_з, k=ГОЛОВА_РУК):
    """(кандидати руки 2, скільки посунуто): перші `k` речей слота руки 1 того ж збору
    не стоять серед перших `k` руки 2, коли в слоті є чим їх замінити.

    Руки 1–2 складаються паралельно й одна одної не бачать; позиційне розведення
    рядка 62 знімає лише збіг НА ТІЙ САМІЙ позиції, і сумка з третього місця руки 1
    могла стояти першою в руці 2. Склад пулу той самий, міняється лише порядок."""
    if not розвести_з:
        return кандидати, 0
    вих, n = {}, 0
    for с, рч in (кандидати or {}).items():
        голова1 = set((розвести_з.get(с) or [])[:k])
        if not голова1 or len(рч) <= k:
            вих[с] = рч
            continue
        свої = [r for r in рч if r.get("id") not in голова1]
        чужі = [r for r in рч if r.get("id") in голова1]
        нова = свої[:k] + чужі + свої[k:] if len(свої) >= k else рч
        n += sum(1 for r in нова[:k] if r.get("id") not in голова1) - sum(1 for r in рч[:k] if r.get("id") not in голова1)
        вих[с] = нова
    return вих, n


def посунути_вже_були(кандидати, вже):
    """(кандидати, звіт): речі з `вже` у кінці свого слота з позначкою `вже_був`.

    Звіт — {посунуто: {слот: n}, без_альтернативи: [слоти, де ВСІ речі вже були]}:
    тиск різноманітності названий і там, де поступитись нема кому."""
    вже = set(вже or ())
    if not вже:
        return кандидати, None
    вих, посунуто, без_альт = {}, {}, []
    for с, рч in (кандидати or {}).items():
        так = [dict(r, вже_був=True) for r in рч if r.get("id") in вже]
        ні = [r for r in рч if r.get("id") not in вже]
        вих[с] = ні + так
        if так:
            посунуто[с] = len(так)
            if not ні:
                без_альт.append(с)
    return вих, dict(вже_були=len(вже), посунуто=посунуто, без_альтернативи=sorted(без_альт))


def рядок_вимоги(знайдено, вже_були=False):
    """Рядок у `правила` пакета: що вона просила з аксесуарів і що робити з речами, що вже були."""
    рядки = []
    # СЛОТИ РЯДКА — ТІ, У ЯКИХ РІЧ СПРАВДІ СТОЇТЬ (24.09.2026, рядок 198). Рядок
    # обіцяє моделі «у пулі такі речі стоять першими», тож називати він має слоти
    # ПІДІБРАНИХ речей, а не всі, що згадала фраза: на `main` «хочеться більше
    # ремінців, шарфів чи кепок» називала «пояс» і «шарф», а шарфів підбір не давав
    # жодного — обіцянка без речей за нею.
    акс = [(ф, [r for r in з["речі"] if r.get("слот") in АКЦЕНТНІ_СЛОТИ])
           for ф, з in знайдено if з and з["речі"]]
    акс = [(ф, рч) for ф, рч in акс if рч]
    if акс:
        рядки.append("Вона просила: %s. Покладай у кожен образ, де це доречно, річ зі слота %s — "
                     "у пулі такі речі стоять першими й несуть поле «за_бажанням»."
                     % ("; ".join("«%s»" % ф for ф, _ in акс),
                        ", ".join("«%s»" % с for с in dict.fromkeys(
                            r.get("слот") for _, рч in акс for r in рч))))
    if вже_були:
        рядки.append("Речі з полем «вже_був» стояли в її образах попереднього збору цього сценарію. "
                     "Бери таку лише тоді, коли іншої речі того самого слота, що підходить, у пулі нема: "
                     "вона просила різноманітності.")
    return " ".join(рядки) or None
