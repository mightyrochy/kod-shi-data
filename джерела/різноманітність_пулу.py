"""різноманітність_пулу.py — бажання жінки читаються слотом і типом, а речі, що вже були в її образах цього сценарію, поступаються рівноцінним (рядок 159).

ЩО ТУТ БУЛО (вердикти тестувальниці «Ір», збірки 22.09 15:32 і 23.09 05:24). Сценарій
«для авто та на урок, дощ», бажання паспорта «кросівки», «джинси», «оригінальний без
зусиль», «яскравий верх». Її слова: «нащо всюди вже в 5 образах ті самі кеди? Невже
немає інших кольорів?», «один і той самий джемпер пригнічує», «хочеться більше
ремінців, шарфів чи кепок». Виміряно на каталог_повний (main 09a27b2):
  · `пакет_моделі.шукати_словами` шукав основу слова в НАЗВІ будь-якої речі й при
    рівному балі брав за абеткою id. На «кросівки» він повертав сукню й три топи, в
    описі яких «з кросівками» (ж-00426@morandi, ж-01662/03016/03018@solmar), — ЖОДНОЇ
    пари взуття; сукня й топи йшли в пул першими «за бажанням». Кросівок у каталозі
    246, кедів 114. Бажання, отже, код не виконував: модель читала «Хоче: кросівки» і
    шукала сама серед чобіт пулу — і брала ту єдину спортивну пару, яка там була;
    «Кеди зелені RENE» (ж-09919@emmeliedelage) — у кожному зборі.
  · той самий пошук на «ремінь» давав чотири сукні («Яскрава сукня … ремінь»), на
    «шарф» — два пальта й блузу, на «кепка» — справжні кепки, але моделі ніхто не
    казав, що вона їх просила.
  · повторний збір «Зібрати ще раз» не знав, що було в попередньому.
ЩО СТАЛО.
  · Фраза бажання читається тим самим класифікатором, яким каталог розкладено по
    слотах (`фід_слот.слот`, `тип_речі`): «кросівки» → взуття/кросівки, «кепка» →
    головний_убір, «ремінь» → пояс, «шарф» → шарф, «джинси» → низ/джинси. Кандидати —
    речі ЦЬОГО слота (і типу, коли фраза його називає): спершу ті, що вже пройшли її
    палітру (пул композитора), потім решта каталогу під жорсткими відсіченнями, як
    доти. Фраза без слота («оригінальний без зусиль») шукається словами, як доти.
  · «акценти» / «яскраві акценти» — речі акцентних слотів (шарф, пояс, головний убір),
    яскравіші першими (хрома C* виміру).
  · Серед речей слота першими ті, що несуть решту її слів у полях, у яких шукає
    `шукати_словами` («біла сукня» — білі сукні; «яскравий верх» — ще й яскравіші).
  · Порядок серед рівних — від сіда збору (у руки 2 він свій): різні збори й руки
    бачать першими різні пари, а не ту саму за абеткою.
  · `вже_були` — id речей із карток попередніх зборів цього сценарію: у слоті вони
    стають у кінець і несуть позначку `вже_був`. Це не замок (CLAUDE.md п.9): річ
    лишається в пулі й законна; модель дістає рядок вимоги, що брати її варто лише
    коли іншої того самого слота нема. Де альтернативи нема, це кажеться полем
    `різноманітність.без_альтернативи`, а не мовчки.
Нового гейта нема: пул не звужується, міняються порядок і те, ЩО саме знайдено за
бажанням.
"""
import random
import re

# акцентні аксесуари, на які вказує слово «акценти» без назви слота
АКЦЕНТНІ_СЛОТИ = ("шарф", "пояс", "головний_убір")
_АКЦЕНТ = re.compile(r"акцент")
_СЛОВО = re.compile(r"[a-zа-яіїєґ0-9']{3,}")


def слот_бажання(фраза):
    """(слот, тип) речі, яку називає фраза бажання, — або (None, None).

    Той самий класифікатор, яким розкладено каталог (`фід_слот.слот`, `тип_речі`):
    бажання й річ говорять одним словником, другого переліку тут не заводиться."""
    import фід_слот as _ФС
    o = {"назва": str(фраза or ""), "категорія": "", "параметри": {}}
    сл = _ФС.слот(o)
    if not сл:
        return None, None
    т = _ФС.тип_речі(o, сл)
    return сл, (т if т and not str(т).endswith("_без_уточнення") else None)


def _основи(фраза):
    """Основи слів фрази (перші 5 літер) — як у `пакет_моделі.шукати_словами`."""
    return [w[:5] for w in _СЛОВО.findall(str(фраза or "").lower())]


# поля, у яких шукає `пакет_моделі.шукати_словами`: бажання й пошук читають ту саму річ
_ПОЛЯ_СЛІВ = ("назва", "тип", "тканина", "візерунок", "колір_назва", "крій")
_ЯСКРАВО = re.compile(r"яскрав")


def _бал(r, фраза):
    """Скільки слів фрази є в полях речі. Основа коротша на закінчення (щонайменше 3
    літери): «біла» / «чорні» — це «білий» / «чорний» поля `колір_назва`."""
    текст = " ".join(str(r.get(к) or "") for к in _ПОЛЯ_СЛІВ).lower()
    return sum(1 for w in _СЛОВО.findall(str(фраза or "").lower())
               if w[:min(5, max(3, len(w) - 2))] in текст)


def _хрома(r):
    """C* виміру речі (0, коли виміру нема) — «яскравіший» для слова «акценти»."""
    lab = r.get("lab") or ()
    return (float(lab[1]) ** 2 + float(lab[2]) ** 2) ** 0.5 if len(lab) >= 3 else 0.0


def _порядок(речі, сід, вже, ключ=None, відкине=None):
    """Речі в порядку сіда (або за `ключ`); ті, що вже були в її образах, і ті, які суд
    цієї погоди відкине (`відкине`), — у кінці."""
    р = list(речі)
    random.Random("%s·бажання" % (сід or 0)).shuffle(р)
    if ключ:
        р.sort(key=ключ)
    зайва = lambda x: (x.get("id") in вже, bool(відкине and відкине(x)))
    return sorted(р, key=зайва)


def речі_бажання(фраза, каталог, кандидати, сід=0, n=4, відсікти=None, вже=(), відкине=None):
    """dict(слоти, тип, речі) — що покласти в пул за цим бажанням; None, коли фраза речі не називає.

    `кандидати` — пул композитора {слот: [речі]} (речі вже в її палітрі); `відсікти`
    — `пакет_моделі._жорстке_відсічення` з температурою й вето цього прогону;
    `відкине` — свідок суду цієї погоди (`вологе_вето`): такі речі йдуть останніми, щоб
    бажання не ставило першою річ, яку суд потім заблокує (замша в дощ, K-WEA-01)."""
    вже = set(вже or ())
    ок = (lambda r: not відсікти(r)) if відсікти else (lambda r: True)
    акцент = bool(_АКЦЕНТ.search(str(фраза or "").lower()))
    if акцент:
        слоти, тип = [с for с in АКЦЕНТНІ_СЛОТИ if с in кандидати], None
        підходить = lambda r: r.get("слот") in слоти
        ключ = lambda r: -_хрома(r)
    else:
        сл, тип = слот_бажання(фраза)
        if not сл or сл not in кандидати:
            return None
        # серед речей слота першими ті, що несуть решту її слів (колір, тканину):
        # «біла сукня» — білі сукні; «яскравий верх» — ще й яскравіші першими
        яскраво = bool(_ЯСКРАВО.search(str(фраза).lower()))
        слоти = [сл]
        ключ = lambda r: (-_бал(r, фраза), -_хрома(r) if яскраво else 0)
        осн = [о for о in _основи(фраза)]
        підходить = ((lambda r: r.get("слот") == сл and r.get("тип") == тип) if тип
                     else (lambda r: r.get("слот") == сл
                           and any(о in str(r.get("назва") or "").lower() for о in осн)))
    if not слоти:
        return None
    з_пулу = [r for с in слоти for r in (кандидати.get(с) or []) if підходить(r)]
    бачені = {r.get("id") for r in з_пулу}
    з_каталогу = [r for r in (каталог or []) if r.get("id") not in бачені and підходить(r) and ок(r)]
    # її слова сильніші за порядок палітри (CLAUDE.md п.9): річ, що несе більше її слів,
    # стоїть першою, звідки б не прийшла; серед рівних — спершу пул, потім каталог
    бал = (lambda x: 0) if акцент else (lambda x: _бал(x, фраза))
    речі = sorted(_порядок(з_пулу, сід, вже, ключ, відкине) + _порядок(з_каталогу, сід, вже, ключ, відкине),
                  key=lambda x: (bool(відкине and відкине(x)), x.get("id") in вже, -бал(x)))[:n]
    # скільки речей, що вже були в її образах, цей підбір оминув — тиск названий числом
    оминуто = sum(1 for r in з_пулу + з_каталогу if r.get("id") in вже) - sum(1 for r in речі if r.get("id") in вже)
    return dict(слоти=слоти, тип=тип, речі=речі, оминуто_вже_були=оминуто)


def вологе_вето(опади):
    """Предикат «суд K-WEA-01 цієї погоди заблокує річ» — або None, коли опади не мокрі.

    Той самий словник і те саме читання полів, що в `суд_погода.погода`: вузьке
    `волокно` перше, рядок складу `матеріал` — запасний."""
    import сценарій as _НАГОДА, суд_погода as _ПОГ
    if str(опади or "") not in _НАГОДА.МОКРІ_ОПАДИ:
        return None
    return lambda r: any(v in str(r.get("волокно") or r.get("матеріал") or "").lower() for v in _ПОГ.ВОЛОГІ_ВЕТО)


ГОЛОВА_РУК = 3   # скільки перших речей слота руки 1 не стоїть на перших місцях руки 2


def розвести_голови(кандидати, розвести_з, k=ГОЛОВА_РУК):
    """(кандидати руки 2, скільки посунуто): перші `k` речей слота руки 1 того ж збору
    не стоять серед перших `k` руки 2, коли в слоті є чим їх замінити.

    Руки 1–2 складаються паралельно й одна одної не бачать; позиційне розведення
    рядка 62 знімає лише збіг НА ТІЙ САМІЙ позиції, і сумка з третього місця руки 1
    могла стояти першою в руці 2. Склад пулу той самий, міняється лише порядок."""
    if not розвести_з:
        return кандидати, 0
    вих, n = {}, 0
    for с, рч in (кандидати or {}).items():
        голова1 = set((розвести_з.get(с) or [])[:k])
        if not голова1 or len(рч) <= k:
            вих[с] = рч
            continue
        свої = [r for r in рч if r.get("id") not in голова1]
        чужі = [r for r in рч if r.get("id") in голова1]
        нова = свої[:k] + чужі + свої[k:] if len(свої) >= k else рч
        n += sum(1 for r in нова[:k] if r.get("id") not in голова1) - sum(1 for r in рч[:k] if r.get("id") not in голова1)
        вих[с] = нова
    return вих, n


def посунути_вже_були(кандидати, вже):
    """(кандидати, звіт): речі з `вже` у кінці свого слота з позначкою `вже_був`.

    Звіт — {посунуто: {слот: n}, без_альтернативи: [слоти, де ВСІ речі вже були]}:
    тиск різноманітності названий і там, де поступитись нема кому."""
    вже = set(вже or ())
    if not вже:
        return кандидати, None
    вих, посунуто, без_альт = {}, {}, []
    for с, рч in (кандидати or {}).items():
        так = [dict(r, вже_був=True) for r in рч if r.get("id") in вже]
        ні = [r for r in рч if r.get("id") not in вже]
        вих[с] = ні + так
        if так:
            посунуто[с] = len(так)
            if not ні:
                без_альт.append(с)
    return вих, dict(вже_були=len(вже), посунуто=посунуто, без_альтернативи=sorted(без_альт))


def рядок_вимоги(знайдено, вже_були=False):
    """Рядок у `правила` пакета: що вона просила з аксесуарів і що робити з речами, що вже були."""
    рядки = []
    акс = [(ф, з) for ф, з in знайдено if з and з["речі"] and set(з["слоти"]) & set(АКЦЕНТНІ_СЛОТИ)]
    if акс:
        рядки.append("Вона просила: %s. Покладай у кожен образ, де це доречно, річ зі слота %s — "
                     "у пулі такі речі стоять першими й несуть поле «за_бажанням»."
                     % ("; ".join("«%s»" % ф for ф, _ in акс),
                        ", ".join("«%s»" % с for с in dict.fromkeys(с for _, з in акс for с in з["слоти"]))))
    if вже_були:
        рядки.append("Речі з полем «вже_був» стояли в її образах попереднього збору цього сценарію. "
                     "Бери таку лише тоді, коли іншої речі того самого слота, що підходить, у пулі нема: "
                     "вона просила різноманітності.")
    return " ".join(рядки) or None
