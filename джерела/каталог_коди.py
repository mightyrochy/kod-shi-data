def запис_для_моделі(розбір, ознаки=None):
    """Поєднує розбір із чинними ознаками каталогу для обох форматів моделі.

    Ознаки заміняють однойменні свідчення розбору, зокрема коли значення відсутнє.
    Без ознак — лише скорочення розбору: без слота, порожніх значень і `features`.
    Вхідні словники лишаються незмінними.
    """
    розбір = розбір if isinstance(розбір, dict) else {}
    # Ознаки каталогу спільні для правил і моделі. Навіть відсутнє значення не
    # підмінюється суперечливим свідком розбору за зміни формату запису.
    поля = {к: v for к, v in розбір.items()
            if к != "features" and (ознаки is None or к not in ПОЛЯ_ЗАПИСУ.values())}
    if ознаки is not None:
        поля.update(ознаки)
    return _коротко(поля) or {}


def особливості(розбір):
    """Рядок особливостей речі як є — або None. Код його не читає й не тлумачить (п.12):
    єдине, що тут робиться, — перевірка, що рядок непорожній."""
    р = (розбір or {}).get("features") if isinstance(розбір, dict) else None
    return str(р).strip() if не_порожній(р) else None


def частка_з_розбором(речі):
    """(з розбором, усього) на переліку речей пулу — «річ без розбору лишається записом як
    сьогодні, і це лічиться» (наряд К-3). Читають проба, A/B і поле `запис` пакета."""
    сп = [r for r in (речі or []) if isinstance(r, dict)]
    return sum(1 for r in сп if r.get("розбір") or r.get("features")), len(сп)


