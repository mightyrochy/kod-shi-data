def рядки_переказу_полів(паспорт):
    """Повертає переказ полів для каналу вимог.

    Проєкція випадку знімає ті самі рядки з `her_words`, щоб слова не дублювали вже передані коди."""
    from паспорт_нагоди import ПРИКРАСИ_БАЖАННЯ
    from паспорт_основи import вето_словами

    п = паспорт or {}
    вето = вето_словами(п)
    рядки = []
    if п.get("бажання"):
        рядки.append("Хоче: " + "; ".join(п["бажання"]))
    if вето:
        рядки.append("Не хоче: " + "; ".join(вето))
    if п.get("настрій"):
        рядки.append("Настрій: " + ", ".join(п["настрій"]))
    # прикраси з цим образом: її бажання на сьогодні
    if п.get("прикраси") in ПРИКРАСИ_БАЖАННЯ:
        рядки.append("Прикраси з цим образом: %s — її бажання на сьогодні" % п["прикраси"])
    return рядки


