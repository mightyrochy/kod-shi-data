# -*- coding: utf-8 -*-
"""каталог_коди.py — РОЗБІР КАТАЛОГУ НА ЖИВОМУ ШЛЯХУ: КОРОТКИЙ ЗАПИС РЕЧІ В ПУЛІ (К-3).

ЧОМУ ЦЕ Є (рішення власника 27.09.2026, `аудит/ПЕРЕДАЧА.md` §0, п. 3 і 4). Модель бачить
~350 речей із ~1 840 придатних за запит — 17 % каталогу (`проби/повтор_каталог.py`), і стеля
тут не в каталозі, а в БЮДЖЕТІ СИМВОЛІВ запиту (`міст_пакет._пакет_у_бюджет`, 120 000).
Розбір каталогу мовною моделлю (`каталог_розбір.py`) дає на річ два виходи: коди закритих
переліків і ОДИН короткий рядок особливостей англійською (`features`, ≤15 слів: відтінок,
фактура, деталі). Отже річ може їхати в пул КОДАМИ Й РЯДКОМ ОСОБЛИВОСТЕЙ замість слів
крамниці — і в той самий бюджет влазить більше речей, без жодного зайвого виклику.

ГОЛОВНА ВИМОГА ВЛАСНИКА, ЯКА ТУТ І ЖИВЕ: «речі не мають втратити своїх особливостей і стати
generic». Тому короткий запис НЕ є «менше фактів»: він міняє СВІДКА (замість української
назви крамниці — коди мовної моделі плюс рядок особливостей), а виміри коду (колір, hex,
сім'я, дуга схеми, осі речі) лишає як є. Рядок `features` код НЕ ЧИТАЄ й не тлумачить
(CLAUDE.md п.12) — лише передає моделі тим самим дротом, що й решту полів.

ПІД ПЕРЕМИКАЧЕМ, ТИПОВО ВИМКНЕНО. Поки власник не звірив A/B (вибір, суд, картки —
`аудит/проби/ab_короткий_запис.py`), пул їде так, як доти: з перемикачем вимкненим ані пул,
ані пакет не міняються ні на байт. Перемикач приходить трьома шляхами, і всі три означають
одне й те саме: `показ.html` (`КОРОТКИЙ_ЗАПИС_П` → поле входу мосту `короткий_запис`),
змінна оточення `ZAPYS_KOROTKYI` (стенд, CLI, проби — оболонка кириличних імен не має) і
прямий аргумент `оголосити()`.

ДЕ САМЕ ДІЄ КОРОТКИЙ ЗАПИС (названо в тілі PR). Лише ПУЛ складання —
`дріт_моделі.пакет` → `pool`: саме його ріже бюджет. Там, де модель бачить УЖЕ ОБРАНІ речі
(склад образу у вердикті, вітрина ремонту, опис), запис лишається повним, і `features`
стоїть ПОРУЧ із ним: збіднювати судження заради бюджету пулу нема сенсу.

ФАЙЛ РОЗБОРУ. `каталог_розбір_коди.json` (або `.gz`) — {id офера: поля
`каталог_розбір.з_відповіді` + "features"}. Лежить ПОРУЧ із модулем, як збагачення й назви
з карток (`назва_речі.читати_назви_карток`), і тим самим шляхом їде у вантаж показу
(`build_артефакт._покласти_розбір`): на телефоні «поруч» — це вантаж. Файла нема — модуль
мовчить, `поля()` віддає порожнє, і кожна річ лишається записом як сьогодні (це лічиться:
`частка_з_розбором`).
"""
import os as _os

import внутрішня_мова as _ВМ

U = _ВМ.UNKNOWN

# Ключ ЗОВНІШНЬОГО контракту: його пише не наш код, а показ, оболонка стенда чи оператор
# на ноутбуці. Декларація стоїть у модулі, а не в сканері (та сама конвенція, що в
# `каблук.ЗОВНІШНІ_ВХОДИ` і `каталог_розбір_прогін.ЗОВНІШНІ_ВХОДИ`).
ЗОВНІШНІ_ВХОДИ = {
    "ZAPYS_KOROTKYI": "перемикач короткого запису речі в пулі для стенда, CLI і проб: 1 — "
                      "коди розбору й рядок особливостей замість слів крамниці; без неї "
                      "запис такий самий, як доти. Показ шле те саме полем `короткий_запис`",
    "ROZBIR_KODY": "шлях до файла розбору каталогу, коли він лежить не поруч із модулем "
                   "(проби, A/B, ноутбук). Без неї береться `каталог_розбір_коди.json[.gz]` "
                   "поруч — той самий шлях, яким файл їде у вантаж показу",
    "короткий_запис": "вхід із показу (`КОРОТКИЙ_ЗАПИС_П`): чи цей прогін пише пул коротким "
                      "записом. Стоїть у ключі кеша пакета (`міст_пакет._входи_пакета`)",
}

РОЗБІР_ІМ = "каталог_розбір_коди.json"
_КЕШ = {}

# ── ЩО З РОЗБОРУ МОДЕЛЬ НЕ БАЧИТЬ ───────────────────────────────────────────────
# `slot` — рішення власника 24–25.09.2026: «модель сама знає, що джинси — низ»; місце речі в
# образі їй не прописується ніде (той самий закон, що в `дріт_моделі.пул`), а слоти веде код.
# `color_from` — де В ТЕКСТІ КРАМНИЦІ названо колір: це факт про текст, не про річ, і жодне
# рішення моделі з нього не виходить (код свідка кольору веде сам — `колір_річ.не_вимір`).
ПОЗА_ЗАПИСОМ = ("slot", "color_from")

# ── «НЕМА ОЗНАКИ» НЕ ПИШЕТЬСЯ, І ЦЕ НЕ ВТРАТА ──────────────────────────────────
# Та сама конвенція, що вже тримає запис речі (`пакет_моделі._річ_пулу`): «поля нема» і
# «ознаки нема» — одне й те саме твердження. Шість вето-ключів словом «no» у кожній речі
# коштували б ~100 символів на річ (на пулі 371 речі — 31 % усього бюджету) і не сказали б
# моделі нічого, чого не каже їхня відсутність. Негативи читає КОД — з того самого файла,
# повним полем (`поля()`), а не зі скороченого запису для моделі.
# «solid» тут теж «нема ознаки», і це не наша вигадка: так його читає сам будівник речі
# («`solid` — службове слово фіду для «без візерунка», не ознака речі», `пакет_моделі._річ_пулу`).
# «one_color» — теж «нема ознаки», і саме за означенням поля: `color_why` існує, щоб сказати,
# ЧОМУ кольорів кілька (два кольори речі, принт, фурнітура, підкладка, варіанти розміру). Коли
# колір один, пояснювати нема чого, і `color_extra` при ньому порожній — тобто те саме
# твердження вже стоїть у записі двічі.
ПОРОЖНІ = (U, "", "no", "none", "not_a_set", "not_stated", "solid", "one_color")

# Стан прогону: чи цей виклик мосту пише пул коротким записом. Оголошується РАЗ на виклик
# (`міст_пакет._пакет_каталогу`), бо будівник речі (`пакет_моделі._річ_пулу`) кличеться і з
# вітрини ремонту, і зі складу образу у вердикті — місць, куди рамка пакета не доходить.
# Мовчазним цей стан не є: те саме значення стоїть у ключі кеша пакета і в полі `запис`
# результату `пакет_для_моделі`, тож на чому зібрано пул — видно, а не вгадується.
_СТАН = {"короткий": None}


def _з_оточення():
    """`ZAPYS_KOROTKYI` → True/False/None (змінної нема — нічого не сказано)."""
    з = _os.environ.get("ZAPYS_KOROTKYI")
    if з is None or str(з).strip() == "":
        return None
    return str(з).strip().lower() not in ("0", "нема", "вимк", "off", "false", "no")


def оголосити(увімкнено=None):
    """Оголосити на цей прогін, чи пул їде коротким записом. `None` — взяти з оточення.

    Явне слово викликача сильніше за оточення (той самий принцип, що в решті шва: «явний
    запит викликача сильніший за мапу»). Віддає ухвалене значення."""
    з = _з_оточення() if увімкнено is None else bool(увімкнено)
    _СТАН["короткий"] = bool(з)
    return _СТАН["короткий"]


def увімкнено():
    """Чи цей прогін пише пул коротким записом. Доки ніхто не оголосив — питається оточення."""
    if _СТАН["короткий"] is None:
        return bool(_з_оточення())
    return _СТАН["короткий"]


def шлях(тека=None):
    """Шлях до файла розбору: `ROZBIR_KODY`, тека аргументом, або поруч із модулем."""
    з_оточення = _os.environ.get("ROZBIR_KODY")
    if з_оточення and не_порожній(з_оточення) and _os.path.exists(з_оточення):
        return з_оточення
    тека = тека or _os.path.dirname(_os.path.abspath(__file__)) or "."
    for ім in (РОЗБІР_ІМ, РОЗБІР_ІМ + ".gz"):
        ш = _os.path.join(тека, ім)
        if _os.path.exists(ш):
            return ш
    return None


def не_порожній(рядок):
    """Рядок має зміст (не None і не пробіли) — одна перевірка на всі шляхи модуля."""
    return bool(str(рядок or "").strip())


def читати(тека=None):
    """{id офера: поля розбору + "features"} — або порожньо, коли файла нема.

    Кеш на (шлях, час зміни), як у `назва_речі.читати_назви_карток`: файл читається раз на
    прогін, а правка файла на диску між прогонами видна без перезапуску."""
    ш = шлях(тека)
    if not ш:
        return {}
    ключ = (ш, _os.path.getmtime(ш))
    if ключ not in _КЕШ:
        import gzip as _gz, json as _json
        with (_gz.open(ш, "rt", encoding="utf-8") if ш.endswith(".gz")
              else open(ш, encoding="utf-8")) as ф:
            _КЕШ.clear()
            _КЕШ[ключ] = _json.load(ф) or {}
    return _КЕШ[ключ]


def поля(ід, тека=None):
    """ПОВНІ поля розбору однієї речі (з "features") — або порожньо. Читає код і проби."""
    if not не_порожній(ід):
        return {}
    з = читати(тека).get(str(ід))
    return з if isinstance(з, dict) else {}


def _коротко(значення):
    """Значення розбору → те саме без «нема ознаки» й без ключів `ПОЗА_ЗАПИСОМ`; порожнє → None.

    Рекурсія на об'єкті (`heel`, `veto`) і на списку об'єктів (`set_parts`) — щоб правило
    «слот не прописується» діяло й на частині комплекту, а не лише на самій речі."""
    if isinstance(значення, dict):
        вих = {к: _коротко(v) for к, v in значення.items() if к not in ПОЗА_ЗАПИСОМ}
        вих = {к: v for к, v in вих.items() if v is not None}
        return вих or None
    if isinstance(значення, (list, tuple)):
        вих = [_коротко(x) for x in значення]
        вих = [x for x in вих if x is not None]
        return вих or None
    if isinstance(значення, str):
        return None if значення.strip().lower() in ПОРОЖНІ else значення
    return значення


def запис_для_моделі(розбір):
    """Поля розбору речі → те, що в КОРОТКОМУ записі бачить модель: коди без слота, без
    «нема ознаки» і без `features` (рядок особливостей кладе `дріт_моделі.річ` окремим полем,
    щоб код ніде не мусив його читати)."""
    if not isinstance(розбір, dict) or not розбір:
        return {}
    return _коротко({к: v for к, v in розбір.items() if к != "features"}) or {}


def особливості(розбір):
    """Рядок особливостей речі як є — або None. Код його не читає й не тлумачить (п.12):
    єдине, що тут робиться, — перевірка, що рядок непорожній."""
    р = (розбір or {}).get("features") if isinstance(розбір, dict) else None
    return str(р).strip() if не_порожній(р) else None


def частка_з_розбором(речі):
    """(з розбором, усього) на переліку речей пулу — «річ без розбору лишається записом як
    сьогодні, і це лічиться» (наряд К-3). Читають проба, A/B і поле `запис` пакета."""
    сп = [r for r in (речі or []) if isinstance(r, dict)]
    return sum(1 for r in сп if r.get("розбір") or r.get("features")), len(сп)
