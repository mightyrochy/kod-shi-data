    """Проєктує відомі поля й дослівні вимоги людини у випадок для моделі.

    Допустимі значення бере зі схеми протоколу. Без паспорта `рядок` може задати подію,
    а відомі нагода й місце їдуть кодами сценарію. Типові значення форми відкидає."""
    import каблук as _КБ8
    import паспорт_поля as _ПП
    import протокол as _ПР
    from паспорт_нагоди import цитата_поля
    from паспорт_основи import вето_чинне, типові_з_форми

    поля = _ПР.ВИПАДОК["поля"]
    в = {}
    for к, v in (паспорт or {}).items():
        if к not in поля or v in (None, "", [], {}):
            continue
        дозволені = поля[к].get("значення")
        if дозволені and v not in дозволені:
            continue
        в[к] = v
    # Паспорт може містити сире вето. На дріт іде цілісне чинне вето для цієї нагоди.
    if isinstance(в.get("вето"), dict) and (паспорт or {}):
        _тв = вето_чинне(паспорт)
        в["вето"] = {к: list(_тв.get(к) or []) for к in в["вето"] if к in _ПР.ВИПАДОК["поля"]["вето"]["поля"]}
        # Застосовність до слота їде разом із межею, що лишилася чинною у цьому списку.
        _сл = {w: list(сл) for w, сл in (_тв.get("слоти") or {}).items()
               if сл and any(w in (в["вето"].get(г) or []) for г in ("кольори", "принти", "тканини", "типи"))}
        if _сл:
            в["вето"]["слоти"] = _сл
    # Коди бажань відповідають тим самим значенням `for_her_wish` у записах пулу.
    _бк = [_ВМ.бажання_кодом(б) for б in ((паспорт or {}).get("бажання_коди") or []) if isinstance(б, dict)]
    if в.get("бажання") and any(_бк):
        в["бажання"] = list(dict.fromkeys(б for б in _бк if б))
    # Типові значення форми лишаються входом правил у сценарії. Її фактом на дроті вони не стають.
    for _к in типові_з_форми(паспорт):
        в.pop(_к, None)
    сц = сценарій or {}
    # Спільний опис полів визначає, що можна взяти прямо зі сценарію та з яким джерелом.
    _зі_сценарію_поля = {}
    for _к in _ПП.поля_стилістці():
        if _к not in в and "мова" not in _ПП.ПОЛЯ_ПАСПОРТА[_к] and сц.get(_к) not in (None, "", [], {}):
            в[_к] = сц.get(_к)
            _зі_сценарію_поля[_к] = (сц.джерело(_к) if hasattr(сц, "джерело")
                                     else _ПП.ПОЛЯ_ПАСПОРТА[_к].get("джерело"))
    if not str(в.get("подія") or "").strip():
        # Нагода й місце сценарію — коди, а назву події бере лише названий людиною вхід.
        for _к in ("нагода", "місце"):
            _v = сц.get(_к)
            if _v and not в.get(_к) and _v in (поля[_к].get("значення") or (_v,)):
                в[_к] = _v
        _зі_сценарію = ", ".join(str(сц.get(к) or "").replace("_", " ").strip()
                                 for к in ("нагода", "місце") if str(сц.get(к) or "").strip())
        # `рядок` — подією лише БЕЗ паспорта (стенд, CLI): це текст входу. З паспортом він — той самий випадок
        # кодами (`паспорт_рядком`), і подією його не ставлять
        в["подія"] = (НЕВІДОМО if (_зі_сценарію or паспорт or not str(рядок or "").strip())
                      else str(рядок))
    # З `her_words` знімаємо переказ полів і службові рядки каблука й переконань.
    # Вони мають свої поля, а дослівний уривок її слів лишається.
    _префікси = (_КБ8.ПРОХАННЯ_РЯДОК, ПЕРЕКОНАННЯ_РЯДОК.split("%s")[0])
    _геть = set(рядки_переказу_полів(паспорт))
    _цитата = ПІДПИС_ЇЇ_СЛІВ % (паспорт or {}).get("слова") if (паспорт or {}).get("слова") else None
    _свої = [(паспорт["слова"] if р == _цитата else р)
             for р in str(вимоги or "").split("\n")
             if р.strip() and р not in _геть and not р.startswith(_префікси)]
    if _свої:
        в["вимоги_людини"] = "\n".join(_свої).strip()
    _прох = _КБ8.прохання(вимоги)
    if _прох:
        в["прохання_взуття"] = _прох
    _перек = [str(x).strip() for x in ((паспорт or {}).get("переконання") or []) if str(x).strip()]
    if _перек:
        в["переконання"] = _перек
    # ЇЇ СЛОВА, ЯКИХ НЕ НЕСЕ ЖОДЕН КОД, — ПОЛЯМИ ВИПАДКУ (М-4). `рядок`
    # дріт рук 1–2 не везе («його факти — у полях поруч», `дріт_моделі.випадок`), а решта сказаного
    # (`решта`, М-1 В-5 — «там завжди холодно в залі і довго стояти в черзі») жила лише в ньому;
    # слова, на яких стоять мета й намір, не жили ніде. На шляху шару рука 1 не діставала жодного.
    if (паспорт or {}).get("причина_ошатності"):
        в["formality_reason"] = паспорт["причина_ошатності"]
    # УРИВОК ПОЛЯ, ЯКЕ СТИЛІСТЦІ ЙДЕ ЛИШЕ КОДОМ (`уривок_стилістці: False`), НЕ ЇДЕ (корінь Е2-частина-дня, 15498):
    # уривок пори — її година («о 20:00»), і стилістка діставала її полем поруч із `part_of_day`
    _цитати = {опис["поле"]: ц for ім, ц in ((паспорт or {}).get("цитати_полів") or {}).items()
               if (опис := _ВМ.ПОЛЯ_ПАСПОРТА.get(ім, {})).get("поле") and опис.get("уривок_стилістці", True)}
    if _цитати:
        в["field_quotes"] = _цитати
    _уривки_бажань = [б.get("уривок") for б in ((паспорт or {}).get("бажання_коди") or []) if б.get("уривок")]
    if _уривки_бажань:
        в["wish_quotes"] = _уривки_бажань
    for _поле in ("мета", "намір"):
        if цитата_поля(паспорт or {}, _поле):
            в[_поле + "_слова"] = цитата_поля(паспорт, _поле)
    # ── ТИПОВИЙ НАМІР — ПРИПУЩЕННЯМ, А НЕ ЇЇ СЛОВОМ (ВИБ-1) ──────────────────────
    # `conventional` паспорт ставить сам, коли вона наміру не назвала («припущення коду, а не її
    # слова», `паспорт_нагоди.виміри_нагоди`). У вибір він уже не їде (`міст_відповіді._випадок_кодами`),
    # а в «case» складання їхав голим `intent: conventional` — як її намір. Поле лишається (пул і
    # доза «на межі» стоять саме на цьому припущенні), але поруч — мітка `намір_звідки`: default.
    # Її слова про намір — цитата `намір_слова` (НАМІР-1): тоді мітки нема, це її намір.
    if в.get("намір") == "conventional" and not str((паспорт or {}).get("намір_слова") or "").strip():
        в["намір_звідки"] = "default"
    if [x for x in (паспорт or {}).get("решта") or [] if str(x).strip()]:
        в["решта"] = [str(x).strip() for x in паспорт["решта"] if str(x).strip()]
    # ПОЯСНЕННЯ МОВНОЇ МОДЕЛІ (НП-в6, принцип власника 01.10): коли її слова про подію важко
    # тлумачити, мовна модель пише стилістці коротко англійською, що вона має на увазі. Код не читає.
    if str((паспорт or {}).get("пояснення_мови") or "").strip():
        в["пояснення_мови"] = str(паспорт["пояснення_мови"]).strip()
    # ── ЧУЖИЙ КОЛІР ПОДІЇ — ФАКТОМ У ВИПАДКУ (МЕЖІ-1, K-KOH-08) ──────────
    # Доти `reserved_colour` мовної моделі діяв пулом (`композитор_придатні`, великі поверхні) і
    # судом (`формальність.нагода_палітра`), а стилістці їхав лише всередині заяви `occasion_level`,
    # яку БРИФ-1 зняв як застосовану. Модель складання не знала, що біле тут належить нареченій, і
    # брала молочний шарф та білі аксесуари, які пул не ріже. Тепер факт стоїть полем
    # `case.reserved_colour` (код переліку, не наказ): вибір лишається за нею (аудит/ПРОДУКТ.md п.17), а
    # пул понад наявне вето не звужується. Наречена поля не має: роль — зі слів жінки.
    _рк = (паспорт or {}).get("зарезервований_колір") or (сценарій or {}).get("зарезервований_колір")
    if _рк in _ВМ.ТАБЛИЦЯ["reserved_colour"]:
        в["зарезервований_колір"] = _рк
    # ЗОНИ МЕТИ «ПРИХОВАТИ»: без них стилістка бачила лише `goal: conceal` поруч із «і ще хочу
    # приховати живіт» і приглушувала ВЕСЬ образ; із ними — знає, що мета стосується зон, а решта образу вільна
    # Зони — з будь-якою увагою; «що ще важливо» — кодами поруч (стилістці — пояснення плиток)
    _зм = [з for з in ((паспорт or {}).get("мета_зони") or []) if з in _ВМ.ТАБЛИЦЯ["goal_zone"].values()]
    if _зм:
        в["мета_зони"] = _зм
    _мв = [к for к in ((паспорт or {}).get("мета_важливо") or []) if к in _ВМ.ТАБЛИЦЯ["goal_extra"].values()]
    if _мв:
        в["мета_важливо"] = _мв
    в["джерела_полів"] = {к: _ПП.походження_поля(паспорт, к) for к in sorted(в) if к != "джерела_полів"}
    for к in в["джерела_полів"]:
        if not _ВМ.ПОЛЯ_ПАСПОРТА.get(к, {}).get("уривок_стилістці", True):
            в["джерела_полів"][к] = {**{x: v for x, v in в["джерела_полів"][к].items() if x not in ("quote", "parts")},
                                    **({"parts": [{x: v for x, v in ч.items() if x != "quote"}
                                                  for ч in в["джерела_полів"][к]["parts"]]}
                                       if в["джерела_полів"][к].get("parts") else {})}   # вид — так, уривок — ні
    if в.get("прохання_взуття"):
        в["джерела_полів"]["прохання_взуття"] = _ПП.походження(_ПП.ВИВЕДЕНЕ)
    if в.get("переконання"):
        в["джерела_полів"]["переконання"] = _ПП.походження(_ПП.ТЛУМАЧЕННЯ)
    for _к, _вид in _зі_сценарію_поля.items():      # поле з опису сценарію — вид з опису, а не з паспорта
        в["джерела_полів"][_к] = _ПП.походження(_вид)
    return в
