def _вид(т):
    """Рядок → токен коду (`a-z0-9_`) або "" — тим самим видом, що й коди переліку, тож
    «a-line» і «a_line», «t-shirt» і «t_shirt» зводяться до одного ключа."""
    return _НЕ_КОД.sub("_", str(т).strip().lower()).strip("_")


_ІНДЕКС = {ш: {_вид(к): к for к in к_ль} for ш, к_ль in ПЕРЕЛІКИ.items()}


def _звести(знач, шлях):
    """Значення моделі поза переліком → код переліку або "unknown". Порядок: зняти пояснення в
    хвості; спробувати ціле значення, потім кожен шматок між роздільниками схеми — у тому
    порядку, як їх написала модель (перший = те, що модель назвала головним). «yes» і «no»
    разом — модель не обрала, тож "unknown", а не перше з двох."""
    коди, син = _ІНДЕКС[шлях], _СИНОНІМИ.get(шлях, {})
    т = _ЗАЙВИЙ_ХВІСТ.sub("", str(знач).strip().lower())
    шматки = [_вид(ш) for ш in _РОЗДІЛЬНИК.split(т)]
    # Ціле значення йде першим (щоб «a-line», «3/4», «no_print», «two_piece_set» не розпалися на
    # шматки), але слово відсутності в ньому читається лише тоді, коли роздільника нема: інакше
    # «no|unknown» на veto читалось би як «того нема» замість коду «no», який стоїть у переліку.
    варіанти = [(_вид(т), len(шматки) == 1)] + [(ш, True) for ш in шматки]
    if "yes" in [в for в, _ in варіанти] and "no" in [в for в, _ in варіанти]:
        return UNKNOWN
    for в, можна_відсутність in варіанти:
        if not в:
            continue
        if в in син:
            return син[в]
        for ф in [в, в + "s"] + ([в[:-1]] if в.endswith("s") else []):
            if ф in коди:
                return коди[ф]
        основа = _ПРИСТАВКА_СИЛИ.sub("", в)
        if основа != в and (основа in син or основа in коди):
            return син[основа] if основа in син else коди[основа]
        if можна_відсутність and (в in _ВІДСУТНІСТЬ or в.startswith("no_")
                                  or в.startswith("without_")):
            return _НЕМАЄ.get(шлях, UNKNOWN)
    return UNKNOWN


# ── СТОРОЖ ЦИТАТ (РЗ-К): КОД ЛИШАЄТЬСЯ, ЛИШЕ КОЛИ ЙОГО СЛОВА Є В ТЕКСТІ РЕЧІ ─
# Старі файли прогону (v1/v2) несли вхід українськими ключами — частини ті самі.
_ЧАСТИНИ_UK = {"назва": "name", "категорія": "category", "опис": "description", "параметри": "params"}
# Де названо колір (`color_from`) — з частини, у якій тримається цитата `color_main` (`ВИВЕДЕНІ`).
_ЗВІДКИ_КОЛІР = {"name": "name", "params": "param", "description": "description"}
# Поля, чию цитату НЕ звіряють зі спільною цитатою типу: вони самі про тип.
_ПРО_ТИП = frozenset(("slot", "item_type", "set_kind"))


def частини_тексту(дані):
    """Вхід моделі (`вхід()` чи запит із файла прогону) → {частина: [рядки]}: назва й опис —
    рядком кожна, поля картки — рядком «ключ: значення» кожне. Цитата тримається, коли стоїть
    в ОДНОМУ рядку, а не на стику двох (як `мовний_шар._тримається` на репліках розмови)."""
    вих = {}
    for к, в in (дані or {}).items():
        ч = _ЧАСТИНИ_UK.get(к, к)
        if ч not in ЧАСТИНИ or not в:
            continue
        вих[ч] = (["%s: %s" % (кк, вв) for кк, вв in в.items()] if isinstance(в, dict) else [str(в)])
    return вих


def _де_тримається(цитата, частини):
    """Частини тексту (порядком `ЧАСТИНИ`), у рядку яких стоїть цитата — `мовний_шар.цитата_тримає`:
    підрядок без словника; регістр, лапки й розділові знаки не важать."""
    if not isinstance(цитата, str) or not цитата.strip():
        return []
    return [ч for ч in ЧАСТИНИ if any(МШ.цитата_тримає(цитата, р) for р in частини.get(ч, ()))]


def вигадка_рядком(шлях, сказала, цитата):
    """Рядок причини про код без опори в тексті речі — будова `мовний_шар.вигадка_рядком`
    (відрізки « · », поле третім), КОДАМИ (п.12): після «=» — лише сирі дані."""
    return ("invented · step=catalog_parse · field=%s · model_said=%s · quote=%s · code=%s"
            % (шлях, json.dumps(сказала, ensure_ascii=False),
               json.dumps(цитата, ensure_ascii=False) if цитата else "none", UNKNOWN))


def _розняти(знач):
    """Пара моделі {quote, value} → (значення, цитата); голий код відповіді v1/v2 → (код, None)."""
    if isinstance(знач, dict) and (ЗНАЧЕННЯ in знач or ЦИТАТА in знач):
        return знач.get(ЗНАЧЕННЯ), знач.get(ЦИТАТА)
    return знач, None


# ── ВІДПОВІДЬ МОДЕЛІ → ПОЛЯ ВНУТРІШНЬОЮ МОВОЮ ───────────────────────────────
def _код(знач, коди, шлях, причини, частини=None, цитати=None):
    """Одне значення моделі (пара чи голий код) → код переліку або "unknown"; кожна вада — рядок
    у `причини`. Значення поза переліком не викидається одразу: спершу `_звести` (РЗ-1) пробує
    впізнати в ньому код. Коли дано `частини` (текст речі), код лишається, лише коли його цитата
    там тримається (`_де_тримається`); інакше "unknown" і рядок `invented`. "unknown" і
    `not_applicable` цитати не потребують. `цитати` (коли дано) дістає {шлях: (цитата, де)}."""
    значення, цитата = _розняти(знач)
    if ВМ.невідомо(значення, коди):
        return UNKNOWN
    т = str(значення).strip().lower()
    if т not in коди:
        зведено = _звести(значення, шлях) if шлях in _ІНДЕКС else UNKNOWN
        if зведено == UNKNOWN:
            причини.append("%s: «%s» поза переліком" % (шлях, str(значення)[:40]))
            return UNKNOWN
        причини.append("%s: «%s» зведено до «%s»" % (шлях, str(значення)[:40], зведено))
        т = зведено
    if частини is None or т in (UNKNOWN, НЕ_СТОСУЄТЬСЯ):
        return т
    де = _де_тримається(цитата, частини)
    if not де:
        причини.append(вигадка_рядком(шлях, значення, цитата))
        return UNKNOWN
    if цитати is not None:
        цитати[шлях] = (цитата, де)
    return т


def _список(знач, коди, шлях, причини, частини=None):
    """Список кодів моделі → список кодів переліку; «unknown», `not_applicable` і порожнє —
    порожній список. Кожен елемент — через `_код` (і сторож цитат, коли дано `частини`)."""
    if знач is None or isinstance(знач, (str, int, float)):
        знач = [] if ВМ.невідомо(знач, коди) else [знач]
    if not isinstance(знач, list):
        причини.append("%s: не список" % шлях)
        return []
    вих = [_код(з, коди, шлях, причини, частини) for з in знач]
    return list(dict.fromkeys(к for к in вих if к not in (UNKNOWN, НЕ_СТОСУЄТЬСЯ)))


def _слот(знач, тип, шлях, причини, частини):
    """Слот: коли тип відомий і стоїть у `внутрішня_мова.СЛОТ_ТИПУ` — слот із таблиці, без цитати
    (та сама пара, що для її власних речей, Ч-4); слово моделі, що з нею не збігається, — рядок
    причини. Інакше — як будь-яке поле: код лише з цитатою."""
    з_таблиці = ВМ.СЛОТ_ТИПУ.get(тип)
    if з_таблиці is None:
        return _код(знач, ПЕРЕЛІКИ[шлях], шлях, причини, частини)
    сказала = _код(знач, ПЕРЕЛІКИ[шлях], шлях, [], None)
    if сказала not in (UNKNOWN, з_таблиці):
        причини.append("%s: з таблиці типу %s — %s, модель сказала %s" % (шлях, тип, з_таблиці, сказала))
    return з_таблиці


# Межа фрагмента — розділовий знак, за яким іде пробіл або кінець рядка (кома в «3,5» — не межа).
_МЕЖА_ФРАГМЕНТА = re.compile(r"[,;.](?=\s|$)")
_КИРИЛИЦЯ = re.compile(r"[Ѐ-ӿ]")


def _обрізати(т):
    """Рядок, довший за `СТЕЛЯ_СЛІВ` слів → (найдовший його початок, що кінчається на межі
    фрагмента й вміщається в стелю, "фрагмента"); коли стелю перевищує вже перший фрагмент —
    (перші `СТЕЛЯ_СЛІВ` слів, "слова"). Слова не переставляються й не міняються."""
    for м in reversed(list(_МЕЖА_ФРАГМЕНТА.finditer(т))):
        початок = т[:м.start()].strip()
        if початок and len(початок.split()) <= СТЕЛЯ_СЛІВ:
            return початок, "фрагмента"
    return " ".join(т.split()[:СТЕЛЯ_СЛІВ]), "слова"


def _фрагменти(знач, причини, частини):
    """Фрагменти `features` (пари {quote, value}) → рядок через кому лише з тих, чия цитата
    тримається в тексті речі (`частини`); решта випадає рядком `invented`. Без `частини` (відповідь
    v1/v2, звірки нема) — усі фрагменти. Рядок, а не пари, — бо його так читає `_особливості`."""
    лишити = []
    for ф in знач:
        значення, цитата = _розняти(ф)
        if not isinstance(значення, str) or not значення.strip() or ВМ.невідомо(значення.strip(" .")):
            continue
        if частини is not None and not _де_тримається(цитата, частини):
            причини.append(вигадка_рядком(ОСОБЛИВОСТІ, значення, цитата))
            continue
        лишити.append(" ".join(значення.split()).strip(" ,;"))
    return ", ".join(dict.fromkeys(л for л in лишити if л))


def _особливості(об, причини, частини=None):
    """Рядок особливостей з відповіді моделі → рядок, що йде далі, або "unknown". Код не читає
    слів — лише ФОРМУ: рядок, кількість слів, латиниця. Кожна вада — рядок у `причини` виду
    «features: <вада> — …» (вади: нема поля, не рядок, список, кілька рядків, обрізано,
    кирилиця); нічого мовчки. "unknown", null і порожнє — відповідь «невідомо», а не вада.
    Кирилиця лишає рядок як є: його читає функціональна модель, і втратити особливості гірше,
    ніж мати їх українською, — але причина названа.
    v3 (РЗ-К): відповідь — список фрагментів-пар; з `частини` фрагмент без опори в тексті
    випадає (`_фрагменти`), а голий рядок без жодної цитати — весь `invented`."""
    if ОСОБЛИВОСТІ not in об:
        причини.append("features: нема поля — unknown")
        return UNKNOWN
    знач = об[ОСОБЛИВОСТІ]
    if isinstance(знач, list) and any(isinstance(х, dict) for х in знач):
        знач = _фрагменти(знач, причини, частини)
    elif частини is not None and знач not in (None, [], "") and not (
            isinstance(знач, str) and ВМ.невідомо(знач.strip(" ."))):
        причини.append(вигадка_рядком(ОСОБЛИВОСТІ, знач, None))
        return UNKNOWN
    if isinstance(знач, list) and знач and all(isinstance(х, str) for х in знач):
        причини.append("features: список — рядків %d, зшито комою" % len(знач))
        знач = ", ".join(х.strip() for х in знач if х.strip())
    if знач is None or знач == [] or знач == "":
        return UNKNOWN
    if not isinstance(знач, str):
        причини.append("features: не рядок — %s, unknown" % type(знач).__name__)
        return UNKNOWN
    if ВМ.невідомо(знач.strip(" .")):                # "unknown", "невідомо", "" — і з крапкою
        return UNKNOWN
    if "\n" in знач.strip():
        причини.append("features: кілька рядків — зшито в один")
    т = " ".join(знач.split())
    слів = len(т.split())
    if слів > СТЕЛЯ_СЛІВ:
        т, межа = _обрізати(т)
        причини.append("features: обрізано — слів %d > %d, лишилось %d по межі %s"
                       % (слів, СТЕЛЯ_СЛІВ, len(т.split()), межа))
    кирилиця = len(_КИРИЛИЦЯ.findall(т))
    if кирилиця:
        причини.append("features: кирилиця — літер %d, рядок лишено" % кирилиця)
    return т


def _звідки_колір(цитати):
    """`color_from` з місця цитати `color_main` (`ВИВЕДЕНІ`): перша частина порядком
    `_ЗВІДКИ_КОЛІР` — назва, поле картки, опис. Назва першою, бо поля картки жниварки несуть і
    хлібні крихти з назвою речі (ж-01232: «категорія_магазину» … «СУКНЯ №1081 ШОКОЛАД»), і
    «param» там збрехав би. «several» не ставиться: на заглушці 7 з 10 речей дістали б його лише
    тому, що опис крамниці повторює назву. Цитати нема —
    "unknown" (тиша тексту не є «not_stated»: код не читає слів, щоб сказати, що кольору нема)."""
    де = (цитати.get("color_main") or (None, ()))[1]
    return next((_ЗВІДКИ_КОЛІР[ч] for ч in _ЗВІДКИ_КОЛІР if ч in де), UNKNOWN)


def з_відповіді(текст, дані=None):
    """Сира відповідь моделі → (поля розбору, причини). Форма відповіді не важить більше за її
    намір (протокол, стійкий розбір): «▁» Lapa знімається, ключі й обрізаний хвіст лікує
    `протокол.розібрати_json`. Значення поза переліком не лишається — на його місці "unknown" і
    названа причина; не JSON — (None, причини). Поля — коди `ПОЛЯ` і рядок особливостей
    `features` (`_особливості`: лише форма).

    `дані` — вхід моделі цієї речі (`вхід()`, чи запит із файла прогону). Коли дано — працює
    СТОРОЖ ЦИТАТ (РЗ-К): кожен код лишається, лише коли його цитата стоїть у тексті речі, інакше
    "unknown" і рядок `invented` у причинах; слот — із типу таблицею (`_слот`), `color_from` — з
    місця цитати кольору (`_звідки_колір`). Без `дані` — читання відповідей v1/v2 як доти (голі
    коди без цитат: заглушка стенда, старі проби)."""
    причини = []
    об = _ПР.розібрати_json((текст or "").replace(ВСТАВКА, ""))
    if not isinstance(об, dict):
        return None, ["не JSON"]
    частини = частини_тексту(дані) if дані is not None else None
    цитати, вих = {}, {}
    for шлях, коди, _ in ПОЛЯ:
        кроки = _кроки(шлях)
        ім, список = кроки[0]
        if частини is not None and (шлях in ВИВЕДЕНІ or шлях == "slot"):
            continue                                   # виводяться після циклу
        if len(кроки) == 1:
            вих[ім] = (_список(об.get(ім), коди, шлях, причини, частини) if список
                       else _код(об.get(ім), коди, шлях, причини, частини, цитати))
        elif список:                                   # set_parts[].<поле>
            частини_набору = об.get(ім)
            частини_набору = частини_набору if isinstance(частини_набору, list) else []
            вих.setdefault(ім, [{} for _ in частини_набору])
            for ч, готова in zip(частини_набору, вих[ім]):
                ч = ч if isinstance(ч, dict) else {}
                if частини is not None and кроки[1][0] == "slot":
                    continue                           # слот частини — з її типу, нижче
                готова[кроки[1][0]] = _код(ч.get(кроки[1][0]), коди, шлях, причини, частини)
        else:                                          # heel.<поле>, veto.<поле>
            гілка = об.get(ім) if isinstance(об.get(ім), dict) else {}
            вих.setdefault(ім, {})[кроки[1][0]] = _код(гілка.get(кроки[1][0]), коди,
                                                       "%s" % шлях, причини, частини, цитати)
    if частини is not None:
        вих["slot"] = _слот(об.get("slot"), вих["item_type"], "slot", причини, частини)
        набір = об.get("set_parts") if isinstance(об.get("set_parts"), list) else []
        for ч, готова in zip(набір, вих.get("set_parts", [])):
            ч = ч if isinstance(ч, dict) else {}
            готова["slot"] = _слот(ч.get("slot"), готова.get("item_type"), "set_parts[].slot",
                                   причини, частини)
        вих["set_parts"] = [{к: г[к] for к in ("slot", "item_type")} for г in вих.get("set_parts", [])]
        вих["color_from"] = _звідки_колір(цитати)
        # СПІЛЬНА ЦИТАТА З ТИПОМ — лише вимір, не вирок: «Шовкова сукня» чесно тримає і тип, і
        # тканину. Скільки кодів спираються лише на слова типу, покаже пілот поруч з еталоном.
        тип = цитати.get("item_type")
        for шлях, (ц, _) in sorted(цитати.items()):
            if тип and шлях not in _ПРО_ТИП and МШ._до_звірки(ц) == МШ._до_звірки(тип[0]):
                причини.append("shared_quote · field=%s · with=item_type" % шлях)
    вих[ОСОБЛИВОСТІ] = _особливості(об, причини, частини)
    порядок = list(dict.fromkeys(_кроки(ш)[0][0] for ш, _, _ in ПОЛЯ)) + [ОСОБЛИВОСТІ]
    вих = {к: вих[к] for к in порядок if к in вих}
    зайві = sorted(к for к in об if к not in вих and к != "id")
    if зайві:
        причини.append("зайві поля: %s" % ",".join(зайві)[:120])
    return вих, причини


def покриття(поля):
    """Які поля розбору річ таки дістала: {шлях: True/False} (список — не порожній, решта — не
    "unknown"); останнім — рядок особливостей `features`. Лічбу по вибірці друкує проба, не цей
    модуль."""
    вих = {}
    for шлях, _, _ in ПОЛЯ:
        кроки = _кроки(шлях)
        в = (поля or {}).get(кроки[0][0])
        if len(кроки) == 1:
            вих[шлях] = bool(в) if кроки[0][1] else (в not in (None, UNKNOWN))
        elif кроки[0][1]:
            вих[шлях] = bool(в) and all(ч.get(кроки[1][0], UNKNOWN) != UNKNOWN for ч in в)
        else:
            вих[шлях] = (в or {}).get(кроки[1][0], UNKNOWN) != UNKNOWN
    вих[ОСОБЛИВОСТІ] = (поля or {}).get(ОСОБЛИВОСТІ) not in (None, UNKNOWN)
    return вих


