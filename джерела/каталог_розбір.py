def _кроки(шлях):
    """Шлях «а[].б» → [("а", True), ("б", False)]: ім'я кроку і чи він список."""
    return [(ч[:-2], True) if ч.endswith("[]") else (ч, False) for ч in шлях.split(".")]


def скелет():
    """Форма відповіді моделі: листок — перелік кодів «a|b|unknown», як його читає
    `збирач_промптів.скелет` (він же підписує листки словами з `ОПИСИ`). Рядок особливостей —
    останнім листком «<…>» (вільний текст, не перелік): модель пише його, уже назвавши коди, тобто
    саме те, чого коди не несуть."""
    с = {}
    for шлях, коди, _ in ПОЛЯ:
        вузол, кроки = с, _кроки(шлях)
        for і, (ім, список) in enumerate(кроки):
            останній = і == len(кроки) - 1
            if останній:
                вузол[ім] = ["|".join(коди)] if список else "|".join(коди)
            elif список:
                вузол = вузол.setdefault(ім, [{}])[0]
            else:
                вузол = вузол.setdefault(ім, {})
    с[ОСОБЛИВОСТІ] = "<%s>" % ОСОБЛИВОСТІ
    return с


