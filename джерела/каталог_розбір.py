# ── ВХІД МОДЕЛІ: СЛОВА КРАМНИЦІ, І ЛИШЕ ВОНИ ────────────────────────────────
# ЧОМУ ЦЕ ОКРЕМА ФУНКЦІЯ, А НЕ `offer["параметри"]`. У полях офера вже лежить ПОПЕРЕДНЄ
# збагачення («слот», «тип», «силует», «довжина_рівень», «виріз_тип», «рукав_рівень»,
# «матеріал_родина», «каблук_см») і службові поля жниварки («бал_інформації», «ранг_відбору»,
# «мова», «знято»). Дати їх моделі — це дати їй ВЛАСНУ ВІДПОВІДЬ і зміряти echo, а не розбір.
# Ознака збагачення в самому фіді: поле має двійника «<поле>_джерело» (`слот_джерело`,
# `виріз_тип_джерело`). Тому правило: геть поле з двійником, геть сам двійник, геть названі
# службові — решта лишається. Поле крамниці «каблук_тип» («Без підборів», «Шпилька») ЛИШАЄТЬСЯ:
# це слова крамниці, і саме на них модель має спертись; «каблук_см» — наш регекс з опису, геть.
СЛУЖБОВІ = frozenset((
    "магазин", "стать", "мова", "знято", "канал", "платформа", "id_магазину", "поля",
    "бал_інформації", "ранг_відбору", "нема_від_магазину", "наявність", "розміри_в_наявності",
    "матеріал_родина", "каблук_см", "слот", "тип", "силует", "довжина", "довжина_рівень",
    "виріз_тип", "рукав_рівень", "вовна_частка", "назва_показу", "назва_показу_джерело",
    "назва_показу_причина", "опис"))
# Поля, які лишаються ЗАВЖДИ, навіть маючи двійника «*_джерело»: двійник тут каже лише, ОДКУДИ
# жниварка взяла слова крамниці (картка чи назва), а не що ми їх витлумачили. Без цього виправлення
# поле кольору бачила б лише частина речей (2 518 з 11 993), і вимір «колір із кількох слів» на
# решті не мав би входу.
ЗАВЖДИ = frozenset(("колір", "каблук_тип", "склад", "розміри", "сезон", "категорія_магазину"))
СТЕЛЯ_ЗНАЧЕННЯ = 400   # довге значення (таблиця мірок, повний опис) обрізається, і це видно
СТЕЛЯ_ПОЛІВ = 60
# Ключем-реченням крамниця пише умови доставки й оплати, а не ознаку речі («способи доставки: у
# відділення нової пошти…»): такий ключ у промпт не йде.
СТЕЛЯ_КЛЮЧА = 40


def поля_крамниці(offer):
    """Поля картки, які написала КРАМНИЦЯ: без попереднього збагачення й службових (`СЛУЖБОВІ`,
    двійники «*_джерело», ключ-речення), окрім названих у `ЗАВЖДИ`. Довге значення обрізається з
    «…», щоб промпт не ріс без межі."""
    пар = offer.get("параметри") or {}
    вих = {}
    for к, в in пар.items():
        if к not in ЗАВЖДИ and (к in СЛУЖБОВІ or к.endswith("_джерело")
                                or ("%s_джерело" % к) in пар or len(к) > СТЕЛЯ_КЛЮЧА):
            continue
        т = str(в).strip()
        if not т:
            continue
        вих[к] = т if len(т) <= СТЕЛЯ_ЗНАЧЕННЯ else т[:СТЕЛЯ_ЗНАЧЕННЯ] + "…"
        if len(вих) >= СТЕЛЯ_ПОЛІВ:
            break
    return вих


def вхід(offer, мова="uk"):
    """Дані одного виклику для `збирач_промптів.зібрати` — ключами того оголошення."""
    значення = (offer.get("назва") or "", offer.get("категорія") or "",
                offer.get("опис") or "", поля_крамниці(offer))
    ключі = (("назва", "категорія", "опис", "параметри") if мова == "uk"
             else ("name", "category", "description", "params"))
    return {к: в for к, в in zip(ключі, значення) if в}


def промпт(offer, мова="uk"):
    """Повідомлення моделі про одну річ: оголошення + дані, шаблоном збирача."""
    return ЗП.зібрати(РОЗБІР[мова], вхід(offer, мова))


# ── ВІДПОВІДЬ МОДЕЛІ → ПОЛЯ ВНУТРІШНЬОЮ МОВОЮ ───────────────────────────────
def _код(знач, коди, шлях, причини):
    """Одне значення моделі → код переліку або "unknown"; кожна вада — рядок у `причини`."""
    if ВМ.невідомо(знач, коди):
        return UNKNOWN
    т = str(знач).strip().lower()
    if т in коди:
        return т
    причини.append("%s: «%s» поза переліком" % (шлях, str(знач)[:40]))
    return UNKNOWN


def _список(знач, коди, шлях, причини):
    """Список кодів моделі → список кодів переліку; «unknown» і порожнє — порожній список."""
    if знач is None or isinstance(знач, (str, int, float)):
        знач = [] if ВМ.невідомо(знач, коди) else [знач]
    if not isinstance(знач, list):
        причини.append("%s: не список" % шлях)
        return []
    вих = [_код(з, коди, шлях, причини) for з in знач]
    return [к for к in вих if к != UNKNOWN]


def з_відповіді(текст):
    """Сира відповідь моделі → (поля розбору, причини). Форма відповіді не важить більше за її
    намір (протокол, стійкий розбір): «▁» Lapa знімається, ключі й обрізаний хвіст лікує
    `протокол.розібрати_json`. Значення поза переліком не лишається — на його місці "unknown" і
    названа причина; не JSON — (None, причини)."""
    причини = []
    об = _ПР.розібрати_json((текст or "").replace(ВСТАВКА, ""))
    if not isinstance(об, dict):
        return None, ["не JSON"]
    вих = {}
    for шлях, коди, _ in ПОЛЯ:
        кроки = _кроки(шлях)
        ім, список = кроки[0]
        if len(кроки) == 1:
            вих[ім] = (_список(об.get(ім), коди, шлях, причини) if список
                       else _код(об.get(ім), коди, шлях, причини))
        elif список:                                   # set_parts[].<поле>
            частини = об.get(ім)
            частини = частини if isinstance(частини, list) else []
            вих.setdefault(ім, [{} for _ in частини])
            for ч, готова in zip(частини, вих[ім]):
                ч = ч if isinstance(ч, dict) else {}
                готова[кроки[1][0]] = _код(ч.get(кроки[1][0]), коди, шлях, причини)
        else:                                          # heel.<поле>, veto.<поле>
            гілка = об.get(ім) if isinstance(об.get(ім), dict) else {}
            вих.setdefault(ім, {})[кроки[1][0]] = _код(гілка.get(кроки[1][0]), коди, шлях, причини)
    зайві = sorted(к for к in об if к not in вих and к != "id")
    if зайві:
        причини.append("зайві поля: %s" % ",".join(зайві)[:120])
    return вих, причини


def покриття(поля):
    """Які поля розбору річ таки дістала: {шлях: True/False} (список — не порожній, решта — не
    "unknown"). Лічбу по вибірці друкує проба, не цей модуль."""
    вих = {}
    for шлях, _, _ in ПОЛЯ:
        кроки = _кроки(шлях)
        в = (поля or {}).get(кроки[0][0])
        if len(кроки) == 1:
            вих[шлях] = bool(в) if кроки[0][1] else (в not in (None, UNKNOWN))
        elif кроки[0][1]:
            вих[шлях] = bool(в) and all(ч.get(кроки[1][0], UNKNOWN) != UNKNOWN for ч in в)
        else:
            вих[шлях] = (в or {}).get(кроки[1][0], UNKNOWN) != UNKNOWN
    return вих


