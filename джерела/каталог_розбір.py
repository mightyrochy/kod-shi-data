def _у_переліку(код, поле):
    """Код коду — лише коли він є у переліку цього поля; інакше None («код сказав слово, якого
    внутрішня мова не має» — це рядок звірки, не тихе «нема»)."""
    return код if код in ПЕРЕЛІКИ.get(поле, ()) else None


def _тип_у_код(тип, збої):
    """Тип коду → код внутрішньої мови. Загальний тип, якого в `ТАБЛИЦЯ["item_type"]` нема
    («сукня», «сумка»), — не None мовчки: він іде рядком у `збої` як прогалина ПЕРЕЛІКУ, бо код
    тут знає більше, ніж внутрішня мова вміє сказати."""
    if not тип:
        return None
    код = _В_КОД["item_type"].get(тип)
    if код is None:
        збої["item_type"] = "поза переліком внутрішньої мови: %s" % тип
    return код


def що_каже_код(offer):
    """Що словники коду кажуть про ЦЮ річ — тими самими полями й кодами, що дає модель.

    Повертає (поля, збої): `поля` — шлях → код або None («код не знає»); `збої` — шлях → текст
    винятку. Виняток не ковтається мовчки (стандарт п.14): він стає рядком звірки, бо впала
    функція коду — теж факт про код."""
    import каблук as КБ
    import verify as V
    import фід_атрибути as ФА
    import фід_взуття as ФВ
    import фід_слот as ФС
    import паспорт_нагоди as ПН
    import траурний_регістр as ТР
    поля, збої = {}, {}

    def взяти(шлях, дія):
        try:
            поля[шлях] = дія()
        except Exception as е:                       # noqa: BLE001 — падіння коду теж факт
            поля[шлях], збої[шлях] = None, "%s: %s" % (type(е).__name__, е)

    слот = None
    взяти("slot", lambda: _В_КОД["slot"].get(ФС.слот(offer)))
    слот = ФС.слот(offer) if "slot" not in збої else None
    назва, пар = offer.get("назва") or "", offer.get("параметри") or {}
    текст = "%s %s" % (назва, offer.get("опис") or "")
    взяти("item_type", lambda: _тип_у_код(ФС.тип_речі(offer, слот), збої))
    взяти("set_kind", lambda: {"костюм": "suit", "костюм_повсякденний": "casual_suit",
                               "комплект": "set"}.get(ФС.тип_набору(offer))
          if слот == "комплект" else ("not_a_set" if слот else None))
    поля["set_parts"] = None                          # переліку частин у коді нема (PR #319)
    # `verify.тканина_зі_слова` уже віддає код латинкою («атлас» → satin) — беремо як є, коли він
    # у переліку; матеріал верху — той самий код, коли він серед матеріалів (шкіра, замша, лак…).
    взяти("fabric", lambda: _у_переліку((V.тканина_зі_слова(назва) or {}).get("тканина"), "fabric"))
    взяти("material", lambda: _у_переліку((V.тканина_зі_слова(назва) or {}).get("тканина"), "material"))
    взяти("cut", lambda: _у_переліку((ФА.крій_з_силуету(offer) or (None,))[0]
                                     or (V.крій_зі_слова(назва) or {}).get("крій"), "cut"))
    взяти("length", lambda: _В_КОД["length"].get((ФА.довжина_речі(offer, слот) or (None,))[0]))
    взяти("sleeve", lambda: _РУКАВ_В_КОД.get(пар.get("рукав_рівень")))
    взяти("neckline", lambda: _ВИРІЗ_В_КОД.get(пар.get("виріз_тип")))
    взуття = {}
    if слот == "взуття":
        взяти("_взуття", lambda: ФВ.взуттєві_атрибути(offer, ФС.тип_речі(offer, слот)) or {})
        взуття = поля.pop("_взуття", None) or {}
    взяти("vamp", lambda: {"низький": "low", "високий": "high"}.get(взуття.get("виріз_стопи")))
    взяти("shaft", lambda: _ХАЛЯВА_В_КОД.get(взуття.get("халява_рівень")))
    взяти("_каблук", lambda: КБ.каблук(назва, пар, offer.get("url")) or {})
    к = поля.pop("_каблук", None) or {}
    поля["heel.present"] = {True: "yes", False: "no"}.get(к.get("є"))
    поля["heel.shape"] = {"тонкий": "thin", "товстий": "block"}.get(к.get("форма"))
    поля["heel.height"] = {"високий": "high", "низький": "low"}.get(к.get("висота"))
    взяти("metal", lambda: _МЕТАЛ_В_КОД.get(ФА.метал(offer, слот)))
    поля["metal_where"] = None                        # поля в коді нема зовсім
    взяти("color_main", lambda: _В_КОД["color_name"].get(
        V.назва_кольору(offer.get("колір_назва") or "") or V.назва_кольору(назва)))
    взяти("color_extra", lambda: [к2 for к2 in (_В_КОД["color_name"].get(V.назва_кольору(с) or "")
                                                for с in (offer.get("кольори_акценти") or []))
                                  if к2] or None)
    поля["color_why"] = None                          # чому кольорів кілька — код не питає
    поля["color_from"] = ("param" if пар.get("колір") else
                          ("name" if V.назва_кольору(назва) else "not_stated"))
    взяти("pattern", lambda: _В_КОД["pattern"].get((V.клас_мотиву(текст) or {}).get("клас")))
    взяти("decor", lambda: [_ОЗДОБА_В_КОД[о] for о in [ТР.святкова_оздоба(offer)]
                            if о in _ОЗДОБА_В_КОД] or None)
    низ = текст.lower()
    for ключ, слово in zip(ВЕТО_КЛЮЧІ, ("смужка", "великий принт", "принт", "блиск", "оверсайз",
                                        "обтисле")):
        взяти("veto.%s" % ключ,
              lambda с=слово: "yes" if any(о in низ for о in ПН.слова_вето(с)) else None)
    return поля, збої


def незгода(код, модель):
    """[(вид, шлях, код, модель)] — рядки для розсуду власника. Види: «незгода» (обидва сказали і
    різне), «код не знає» (виграш розбору), «модель не знає» (втрата)."""
    рядки, пм = [], покриття(модель) if модель else {}
    for шлях, _, _ in ПОЛЯ:
        кроки = _кроки(шлях)
        м = (модель or {}).get(кроки[0][0])
        if len(кроки) == 2 and not кроки[0][1]:          # heel.<поле>, veto.<поле>
            м = (м or {}).get(кроки[1][0])
        elif len(кроки) == 2:                            # set_parts[].<поле> — листок кожної частини
            м = [ч.get(кроки[1][0]) for ч in (м or []) if ч.get(кроки[1][0], UNKNOWN) != UNKNOWN]
        к = (код or {}).get(шлях)
        є_м = пм.get(шлях, False)
        if isinstance(м, list):
            м = sorted(м)
        if not к and є_м:
            рядки.append(("код не знає", шлях, None, м))
        elif к and not є_м:
            рядки.append(("модель не знає", шлях, к, None))
        elif к and є_м:
            свої = ЗЛИТІ.get(шлях, {}).get(к, {к})
            збіг = (set(м) & set(к if isinstance(к, list) else [к])) if isinstance(м, list) else (м in свої)
            if not збіг:
                рядки.append(("незгода", шлях, к, м))
    return рядки


