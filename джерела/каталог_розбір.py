def що_каже_код(offer):
    """Що словники коду кажуть про ЦЮ річ — тими самими полями й кодами, що дає модель.

    Повертає (поля, збої): `поля` — шлях → код або None («код не знає»); `збої` — шлях → текст
    винятку. Виняток не ковтається мовчки (стандарт п.14): він стає рядком звірки, бо впала
    функція коду — теж факт про код."""
    import каблук as КБ
    import verify as V
    import фід_атрибути as ФА
    import фід_взуття as ФВ
    import фід_слот as ФС
    import паспорт_нагоди as ПН
    import траурний_регістр as ТР
