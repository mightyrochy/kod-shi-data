# ── СКЕЛЕТ ВІДПОВІДІ І СХЕМА: З ОДНОГО Й ТОГО САМОГО `ПОЛЯ` ─────────────────
def _кроки(шлях):
    """Шлях «а[].б» → [("а", True), ("б", False)]: ім'я кроку і чи він список."""
    return [(ч[:-2], True) if ч.endswith("[]") else (ч, False) for ч in шлях.split(".")]


def _листки():
    """[(шлях, коди, опис)] полів, які пише МОДЕЛЬ: `ПОЛЯ` без `ВИВЕДЕНІ`."""
    return [(ш, к, о) for ш, к, о in ПОЛЯ if ш not in ВИВЕДЕНІ]


def скелет():
    """Форма відповіді моделі, як її бачить промпт: кожне поле — {"quote": "<quote>", "value":
    "a|b|unknown — опис"} (`збирач_промптів` кладе цей словник як є). Цитата стоїть ПЕРШОЮ:
    модель спершу шукає слова в тексті, а вже тоді обирає код — без слів лишається "unknown".
    Рядок особливостей — останнім, списком фрагментів тієї самої форми."""
    с = {}
    for шлях, коди, опис in _листки():
        # Частини набору беруть ті самі переліки, що й річ: посилання замість другої копії
        # (~1 300 знаків промпта); перелік у граматиці відповіді стоїть повний.
        перелік = ("<a code from the \"%s\" list>" % _кроки(шлях)[-1][0]
                   if шлях.startswith("set_parts[]") else "|".join(коди))
        лист = {ЦИТАТА: "<%s>" % ЦИТАТА, ЗНАЧЕННЯ: "%s — %s" % (перелік, опис)}
        вузол, кроки = с, _кроки(шлях)
        for і, (ім, список) in enumerate(кроки):
            if і == len(кроки) - 1:
                вузол[ім] = [лист] if список else лист
            elif список:
                вузол = вузол.setdefault(ім, [{}])[0]
            else:
                вузол = вузол.setdefault(ім, {})
    с[ОСОБЛИВОСТІ] = [{ЦИТАТА: "<%s>" % ЦИТАТА, ЗНАЧЕННЯ: "<%s>" % ОПИС_ОСОБЛИВОСТЕЙ}]
    return с


def _пара(значення):
    """Схема однієї пари {quote, value}: цитата — рядок у стелі, значення — `значення`."""
    return {"type": "object", "additionalProperties": False, "required": [ЦИТАТА, ЗНАЧЕННЯ],
            "properties": {ЦИТАТА: {"type": "string", "maxLength": СТЕЛЯ_ЦИТАТИ},
                           ЗНАЧЕННЯ: значення}}


def _обʼєкт():
    return {"type": "object", "additionalProperties": False, "required": [], "properties": {}}


def схема_відповіді():
    """JSON Schema ВІДПОВІДІ МОДЕЛІ — `response_format` виклику LM Studio (прогін). Граматика з
    неї не пускає ні переказу промпта замість відповіді, ні коду поза переліком, ні голого коду
    без цитати. Усі поля обов'язкові: пропуск поля — теж відповідь, і вона має бути "unknown".
    Без описів: їх несе скелет промпта, а граматиці вони ні до чого."""
    корінь = _обʼєкт()
    for шлях, коди, _ in _листки():
        вузол, кроки = корінь, _кроки(шлях)
        for і, (ім, список) in enumerate(кроки):
            if ім not in вузол["required"]:
                вузол["required"].append(ім)
            if і == len(кроки) - 1:
                лист = _пара({"enum": коди})
                вузол["properties"][ім] = ({"type": "array", "maxItems": СТЕЛІ_СПИСКІВ[ім],
                                            "items": лист} if список else лист)
                continue
            if ім not in вузол["properties"]:
                вузол["properties"][ім] = ({"type": "array", "maxItems": СТЕЛІ_СПИСКІВ[ім],
                                            "items": _обʼєкт()} if список else _обʼєкт())
            вузол = вузол["properties"][ім]
            вузол = вузол["items"] if список else вузол
    корінь["required"].append(ОСОБЛИВОСТІ)
    корінь["properties"][ОСОБЛИВОСТІ] = {
        "type": "array", "maxItems": СТЕЛЯ_ФРАГМЕНТІВ,
        "items": _пара({"type": "string", "maxLength": СТЕЛЯ_ФРАГМЕНТА})}
    return корінь


def схема():
    """JSON Schema розбору — з тих самих `ПОЛЯ`, що й скелет промпта й перевірка відповіді.
    Породжує файл `каталог_розбір.schema.json` (`python3 джерела/каталог_розбір.py`), як
    `внутрішня_мова.схема()` породжує свій. `$defs.catalog_parse` — що лягає в `розбір.json`
    (коди без цитат), `$defs.model_answer` — що пише модель (`схема_відповіді`)."""
    корінь = {"type": "object", "additionalProperties": False, "required": ["id"],
              "description": "розбір однієї речі каталогу мовною моделлю",
              "properties": {"id": {"type": "string",
                             "description": ("id речі в каталозі; його дописує прогін, у моделі "
                                             "його не питають — вона не має чого echo-їти")}}}
    for шлях, коди, опис in ПОЛЯ:
        вузол, кроки = корінь, _кроки(шлях)
        for і, (ім, список) in enumerate(кроки):
            if і == len(кроки) - 1:
                лист = {"description": опис, "enum": коди}
                вузол["properties"][ім] = ({"type": "array", "items": лист} if список else лист)
                continue
            далі = вузол["properties"].setdefault(ім, {})
            if список:
                далі.setdefault("type", "array")
                далі.setdefault("description", "частини набору")
                далі = далі.setdefault("items", {})
            далі.setdefault("type", "object")
            далі.setdefault("additionalProperties", False)
            далі.setdefault("properties", {})
            вузол = далі
    корінь["properties"][ОСОБЛИВОСТІ] = {
        "type": "string", "x-стеля-слів": СТЕЛЯ_СЛІВ,
        "description": ("рядок англійською, до %d слів: фрагменти моделі, чиї цитати тримаються, "
                        "через кому, або unknown. Вільний текст для функціональної моделі; код його "
                        "не читає і перевіряє лише форму (рядок, кількість слів, латиниця)"
                        % СТЕЛЯ_СЛІВ)}
    return {"$schema": "https://json-schema.org/draft/2020-12/schema", "$id": ВЕРСІЯ,
            "title": "Розбір каталогу Люстерка",
            "description": ("Поля, якими мовна модель описує річ каталогу для коду: коди із "
                            "закритих переліків, \"not_applicable\" (поля в такої речі не буває) або "
                            "\"unknown\" (опори в тексті крамниці нема — вигадувати не можна). "
                            "Модель відповідає парами {quote, value} (`model_answer`); код лишає "
                            "значення лише тоді, коли цитата стоїть у тексті речі. Переліки slot, "
                            "item_type, fabric, material, pattern, color_name, length, shaft — ті "
                            "самі, що в `внутрішня_мова.ТАБЛИЦЯ`; cut — `силует_крої.КРОЇ`. Поруч "
                            "із кодами — рядок особливостей `features` англійською для "
                            "функціональної моделі. Породжує файл `каталог_розбір.схема()`; вхід "
                            "моделі — `каталог_розбір.вхід()`."),
            "x-форми-unknown": list(ВМ.ФОРМИ_НЕВІДОМО),
            "x-виведені-кодом": sorted(ВИВЕДЕНІ) + ["slot (СЛОТ_ТИПУ)", "set_parts[].slot (СЛОТ_ТИПУ)"],
            "x-звідки-код-бере-сьогодні": ЗВІДКИ,
            "$defs": {"catalog_parse": корінь, "model_answer": схема_відповіді()}}


