# -*- coding: utf-8 -*-
"""місце_речі.py — ОДИН ЗАПИС МІСЦЯ РЕЧІ НА НІЙ З ПОХОДЖЕННЯМ (корінь Е3-місце-речі, `аудит/корені/Е3-місце-речі.md`,
«Інваріант ПІСЛЯ»).

Де річ на ній, що вона закриває і що закриває її, код знає лише з трьох джерел — і лише ці три тут пишуться:
  · «вимір» — вимір коду: `near` речі з маски на її кадрі чи кадрі примірки (`areas.near_share`, копія —
    `pipeline`) або з геометрії речі на її тілі (`areas.образ_з_геометрії`); інших писачів поля `near` речі в
    продукті нема;
  · «стилістка» — слово стилістки, що збирає образ, у схемі її відповіді під її власним ім'ям — поле речі
    `місце_стилістки` (`біля_обличчя`, `видно`: «так»/«ні»; `слова` — як вона це сказала: «шарф під
    підборіддям», «светр під застебнутим пальтом не видно»);
  · «тип» — факт, однаковий для кожної речі слота при будь-якому вдяганні (`ФАКТИ_СЛОТА`, `ПІД_ВЕРХНІМ_ШАРОМ`);
решта — «невідомо» (None). Сталої класу тут нема: берет на потилиці й шарф під підборіддям слот не розрізняє.

ЗАПИС — словник `місце_речі` на елементі образу (`outfit.елементи`) чи з `записати(річ)` для речі поза ним:
  біля_обличчя   частка приобличчевого поля 0..1 або None — «невідомо»;
  джерело        "вимір" | "стилістка" | "тип" | "невідомо" — звідки `біля_обличчя`;
  факт_типу      `ФАКТИ_СЛОТА` для слота речі (1.0 / 0.0) або None: факт, однаковий для кожної речі слота, певний
                 і тоді, коли `біля_обличчя` взято з виміру без похибки (сережка — біля обличчя);
  під_шаром      id речі верхнього шару, під якою річ у стані «надворі», або None;
  видно          частка речі, яку видно з-під шару: 1.0 — не під шаром; 0.0 — стилістка сказала «не видно»;
                 None — «невідомо» (під шаром, і ні вимір, ні стилістка не сказали скільки);
  видно_джерело  "тип" | "стилістка" | "невідомо";
  слова          слова стилістки, коли джерело — вона, інакше None.

ЧИТАЧ (`бік_межі`, `біля_обличчя_відоме`) бере те, що має викликач, — елемент чи річ із записом, річ без запису
(запише сам) чи сам запис; інша форма — виняток `ФормаВходу`. З «невідомо» читач мовчить чи дає «без входу» і сталої
не підставляє. Поле `near`
елемента лишається для читачів, ще не переведених на запис (перелік — паспорт кореня, «Стан і що лишилось»):
воно досі бере `колір_річ.near_слота`, коли виміру нема, і тому для них — місце кореня, не запис.
"""

ДЖЕРЕЛА = ("вимір", "стилістка", "тип", "невідомо")

# ФАКТ СЛОТА — однаковий для кожної речі слота, хоч як її вдягнено: сережки — на вухах, тобто біля обличчя;
# окуляри — на обличчі; взуття, шкарпетки, колготи й низ — нижче за пояс, тобто не біля нього; браслет — на
# зап'ясті, каблучка — на пальці, пояс — на талії, сумка — у руці чи на плечі (рішення менеджера 08.11, #3385). Головного убору, шарфа, прикрас на шиї й
# руках, верху й верхнього шару тут нема: де вони відносно обличчя, залежить від того, як вдягнено (берет на
# потилиці, шарф на сумці, довге намисто до пояса, каблучка на руці біля щоки).
ФАКТИ_СЛОТА = {"сережки": 1.0, "окуляри": 1.0, "взуття": 0.0, "шкарпетки": 0.0, "колготи": 0.0, "низ": 0.0,
               "браслет": 0.0, "каблучка": 0.0, "пояс": 0.0, "сумка": 0.0}

# Верхній шар вдягають поверх одягу — факт для кожного пальта й куртки; СКІЛЬКИ речі під ним видно, — ні: це
# залежить від довжини шару, стану застібки й того, що річ виступає (комір, горловина, поділ сукні).
ПІД_ВЕРХНІМ_ШАРОМ = ("верх", "сукня", "комплект", "низ")
ВЕРХНІЙ_ШАР = "верхній_шар"

_ТАК = ("так", "yes", True)
_НІ = ("ні", "no", False)


def _слово(значення):
    """«так»/«ні» стилістки → 1.0 / 0.0; інше (нема, «частково», «не знаю») → None."""
    if isinstance(значення, str):
        значення = значення.strip().lower()
    if значення in _ТАК:
        return 1.0
    if значення in _НІ:
        return 0.0
    return None


def записати(річ, шар=None):
    """Запис місця речі з походженням. `шар` — річ верхнього шару образу в стані «надворі» (None — шару нема чи
    стан «у приміщенні»)."""
    стилістка = річ.get("місце_стилістки") or {}
    слова = стилістка.get("слова") if стилістка else None
    вимір = річ.get("near")
    біля, джерело = None, "невідомо"
    if вимір is not None:
        біля, джерело = float(вимір), "вимір"
    elif _слово(стилістка.get("біля_обличчя")) is not None:
        біля, джерело = _слово(стилістка.get("біля_обличчя")), "стилістка"
    elif річ.get("слот") in ФАКТИ_СЛОТА:
        біля, джерело = ФАКТИ_СЛОТА[річ["слот"]], "тип"
    під = шар.get("id") if шар is not None and шар is not річ and річ.get("слот") in ПІД_ВЕРХНІМ_ШАРОМ else None
    if під is None:
        видно, видно_джерело = 1.0, "тип"
    elif _слово(стилістка.get("видно")) is not None:
        видно, видно_джерело = _слово(стилістка.get("видно")), "стилістка"
    else:
        видно, видно_джерело = None, "невідомо"
    return dict(біля_обличчя=біля, джерело=джерело, факт_типу=ФАКТИ_СЛОТА.get(річ.get("слот")), під_шаром=під, видно=видно, видно_джерело=видно_джерело,
                слова=слова if "стилістка" in (джерело, видно_джерело) else None)


def записати_образ(речі, стан="у_приміщенні"):
    """id речі → запис місця для образу в стані `стан`. «Надворі» верхній шар — над одягом (`ПІД_ВЕРХНІМ_ШАРОМ`);
    «у приміщенні» його не вдягнено, і під шаром нема нічого."""
    шар = next((р for р in речі if р.get("слот") == ВЕРХНІЙ_ШАР), None) if стан == "надворі" else None
    return {р.get("id"): записати(р, шар) for р in речі}


# ФОРМИ ВХОДУ ЧИТАЧА — те, що має викликач (рішення менеджера 08.11 на КОЛО #3352, паспорт кореня, «Рішення»):
#   · елемент образу чи річ із записом — словник з ключем `місце_речі` (запис — словник; None — запису нема);
#   · річ без запису — словник речі (`РІЧ_КЛЮЧІ`): запис робить `записати` тут, бік межі від шару не залежить;
#   · сам запис — словник лише з `ЗАПИС_КЛЮЧІ`, з `джерело` із `ДЖЕРЕЛА`.
# Інша форма (рядок слота, None, словник без жодного з цих ключів, запис з чужим ключем) — виняток `ФормаВходу`,
# а не «невідомо»: запис, переданий замість елемента, тихо давав None — законну відповідь (коло #3352, #3357).
# Викликач `записати` для читання не кличе й запису в `dict(місце_речі=…)` не загортає.
ЗАПИС_КЛЮЧІ = ("біля_обличчя", "джерело", "факт_типу", "під_шаром", "видно", "видно_джерело", "слова")
РІЧ_КЛЮЧІ = ("слот", "тип", "near", "місце_стилістки", "id", "ід")


class ФормаВходу(TypeError):
    """Читачеві запису дали не елемент, не річ і не запис."""


def _елемент(вхід):
    """Вхід читача, зведений до елемента з записом `місце_речі`: елемент чи річ із записом — як є, річ без запису —
    з записом `записати` (без шару: бік межі від шару не залежить), сам запис — у полі. Одна точка зведення —
    тут, а не обгортка `dict(місце_речі=…)` у кожного викликача."""
    if not isinstance(вхід, dict):
        raise ФормаВходу("місце_речі: читач бере елемент, річ чи запис місця, а не %s" % type(вхід).__name__)
    if "місце_речі" in вхід:
        запис = вхід["місце_речі"]
        if запис is None:
            return dict(вхід, місце_речі=записати(вхід))
        if isinstance(запис, dict) and _це_запис(запис):
            return вхід
        raise ФормаВходу("місце_речі: поле `місце_речі` — не запис місця (%r)" % (запис,))
    if _це_запис(вхід):
        return {"місце_речі": вхід}
    if any(к in вхід for к in РІЧ_КЛЮЧІ):
        return dict(вхід, місце_речі=записати(вхід))
    raise ФормаВходу("місце_речі: словник — не елемент, не річ і не запис місця (ключі: %s)"
                     % (", ".join(map(str, вхід)) or "порожній"))


def _це_запис(словник):
    return ("джерело" in словник and словник["джерело"] in ДЖЕРЕЛА
            and all(к in ЗАПИС_КЛЮЧІ for к in словник))


def біля_обличчя_відоме(вхід):
    """Частка приобличчевого поля з запису або None — «невідомо» (читач мовчить чи дає «без входу»).
    Вхід — елемент, річ чи запис (`_елемент`); інша форма — `ФормаВходу`."""
    return _елемент(вхід)["місце_речі"].get("біля_обличчя")


def бік_межі(вхід):
    """Бік межі «біля обличчя» з запису місця речі: True / False, або None — бік не певний чи невідомий.
    Вхід — елемент образу чи річ із записом, річ без запису чи сам запис (`_елемент`); інша форма — `ФормаВходу`.

    Виміряна частка `near` з маски — без похибки (її код не знає), тож порогу з нею не порівнюють: бік не
    певний (Е3-одна-величина, «Рішення» 08.11, слово власника 08.11 10:07: вимір є, певності нема). «Тип» і
    «стилістка» дають 1.0 / 0.0 — це вже «так» / «ні», не частка. Факт типу (`факт_типу`) стоїть над виміром: він
    певний. Нема частки — «невідомо».
    Єдина точка для читачів запису: порогу своєї сторони вони не вирішують."""
    запис = _елемент(вхід)["місце_речі"]
    if запис.get("факт_типу") is not None:
        return bool(запис["факт_типу"])
    біля = запис.get("біля_обличчя")
    if біля is None or запис.get("джерело") == "вимір":
        return None
    return bool(біля)
