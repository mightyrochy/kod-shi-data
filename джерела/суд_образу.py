        # НІКОЛИ, і п'ять правил судили над рівномірною константою — при тому, що
        # в тому самому словнику поруч стояло `походження_площ: "не виміряно"`.
        #
        # ВИМІРЯНО 08.09.2026 на одному образі з шести речей (блуза, штани, човники,
        # сережки, шарф, брошка), два прогони — заглушка проти масок:
