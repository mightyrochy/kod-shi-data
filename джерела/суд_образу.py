def для_стиліста(результат):
    """КОНТРАКТ ВИХОДУ. Система — помічник ші-стиліста: вона МІРЯЄ, проганяє всі правила
    і віддає по кожному СИЛУ ВПЛИВУ неперервною величиною. Вона не арбітрує: там, де
    правила розходяться (K-COL-CONF), вибір лишається стилістові.

    Кожен рядок несе ДВІ ОРТОГОНАЛЬНІ ОСІ, які не змішуються:
      • `сила_нп` ∈ [0,1] — сила властивості (наскільки далеко за поріг зайшов ВИМІР);
      • `джерело_сили` — чи це вимір, чи виведено з категорії (тоді точність не вдається);
      • `регістр` — заявлений авторитет (може бути обмежений: R-PC-03 не дає слабшій осі
        звучати голосніше за захищенішу), а `блокує` — НЕ вирок, а мітка «правило-гейт
        порушене»; що з цим робити, вирішує стиліст.
    Плюс `ремонти` зі структурованими вікнами (машиночитними, не текстом) і `де_ламається`.

    `сила` (КАТЕГОРІЯ корпусу) їде поруч із `сила_нп` (Т-03, 12.09.2026). Доти рядок
    ніс лише число, і `обмежити_вагу` нижче за течією (`composer._оцінити`,
    `pipeline.знахідки_вердикту`) не мала за що ставити стелю: `_КАТ_У_НП.get(None)`
    — нема стелі. Виміряно на живому шляху: пʼять K-KOH-05 виходили з `сила=None`
    до моделі й у журнал — V10 («обмежити_вагу не на шляху до моделі») стояла й
    після її виклику. Це не другий вирок, а та сама категорія, з якої число вже
    порахували в `_неперервна_сила`."""
    вих = {}
    for стан, d in (результат.get("стани") or {}).items():
        рядки = []
        for z in d.get("знахідки", []):
            if z.get("сила") == "ok":
                continue
            рядки.append(dict(
                правило=z.get("правило"),
                сила=z.get("сила"),
                сила_нп=z.get("сила_нп"),
                джерело_сили=z.get("сила_нп_джерело"),
                регістр=z.get("регістр"), блокує=bool(z.get("блокує")),
                обмежено=z.get("обмежено"),
                суть=z.get("суть"), чому=z.get("чому"),
                речі=z.get("речі"),
                ремонти=(z.get("ремонт") if isinstance(z.get("ремонт"), list)
                         else ([z["ремонт"]] if z.get("ремонт") else [])),
                варіантів=len(z.get("ремонт") or []) if isinstance(z.get("ремонт"), list)
                          else (1 if z.get("ремонт") else 0),
                вікно=z.get("запит_у_каталог"),
                де_ламається=z.get("де_ламається"),
                поріг=z.get("поріг"),
                питання=z.get("питання_людині")))
        # НЕ СОРТУЄМО за силою. Сила кожного правила — ВЛАСНА шкала: 0.7 у K-CLR-02 і
        # 0.7 у K-COL-05 міряють різні речі й не взаємозамінні. Сортування за силою
        # нав'язало б ші-стилістові міжправиловий пріоритет, якого система не має права
        # встановлювати. Порядок — стабільний (за правилом, тоді за річчю), щоб вихід був
        # відтворюваний, а не щоб щось було «важливішим».
        рядки.sort(key=lambda r: (str(r["правило"]), str(r["речі"])))
        вих[стан] = рядки
    return dict(стани=вих, сценарій=результат.get("сценарій"),
                арбітраж="за стилістом: система міряє, проганяє всі правила й віддає силу "
                         "впливу по кожному; вироку й зведеного балу не дає",
                шкали="сила_нп у кожного правила своя і між правилами НЕ порівнюється; "
                      "порядок рядків стабільний, не рейтинговий",
                варіативність="кілька ремонтів на знахідку і кілька вікон під один слот — "
                              "простір вибору в межах правил, а не одна прописана відповідь",
                не_зроблено=не_зроблено())


def перевірити_контракт(результат):
    """Інваріант: КОЖНА знахідка несе неперервну силу й названо, звідки вона. Якщо
    майбутнє правило віддасть лише бакет — цей чек його зловить."""
    порушення = []
    for стан, d in (результат.get("стани") or {}).items():
        for z in d.get("знахідки", []):
            if z.get("сила") == "ok": continue
            if "сила_нп" not in z:
                порушення.append((стан, z.get("правило"), "нема поля сила_нп"))
            elif z["сила_нп"] is None and not z.get("сила_нп_джерело"):
                # None законний (виміру нема), але причина мусить бути названа
                порушення.append((стан, z.get("правило"), "сила None без причини"))
            elif not z.get("сила_нп_джерело"):
                порушення.append((стан, z.get("правило"), "нема джерела сили"))
        # ── ПЛОЩОЗАЛЕЖНЕ ПРАВИЛО НЕ СУДИТЬ ПІДМНОЖИНУ ОБРАЗУ (Н-outfit-1-084) ──
        # Політика секції «ПЕРЕВІРКИ ОБРАЗУ» каже: елемент без виміряної площі до
        # площозалежного рішення не входить. Сама по собі вона безпечна лише доки
        # хтось стежить, що таке правило не ВИНЕСЛО вердикту над рештою речей —
        # інакше «≤3 сім'ї» чи «понад бюджет» порахувались би на половині образу й
        # звучали б так само впевнено. Тут це і перевіряється: реєстр
        # `ПЛОЩОЗАЛЕЖНІ_ІД` × наявність елемента без площі в тому самому стані.
        # Утримана знахідка законна — вона саме про те, що виміру нема.
        нема_площі = sorted({e.get("річ") for e in (d.get("елементи") or [])
                             if e.get("площа") is None})
        if нема_площі:
            for z in d.get("знахідки", []):
                if (z.get("правило") in ПЛОЩОЗАЛЕЖНІ_ІД
                        and z.get("сила") not in ("утримано", "ok")):
                    порушення.append((стан, z.get("правило"),
                                      "площозалежне правило вийшло, хоч площа не виміряна в %s"
                                      % ", ".join(str(x) for x in нема_площі)))
    return порушення

