def камера_проти_життя(E):
    """[знахідки] K-CRA-10: камера ≠ життя, і наш власний рендер — фотографія.

    ЩО САМЕ ТУТ СТВЕРДЖУЄТЬСЯ. Не «образ поганий». Стверджується рівно те, що
    корпус називає зміщенням ВЛАСНОГО каналу: фактурний контраст на фотографії
    майже зникає, а приміряння людина бачить саме рендером. Отже образ, чий
    інтерес тримається ЛИШЕ на фактурі, у рендері виглядатиме порожнішим, ніж він
    є, — і жінка судитиме його по картинці.

    Сила `hint` — так дає корпус. Умова однобічна: ні хроми, ні принту, сама
    фактура. Коли інтерес несе колір або принт, зміщення каналу знахідки не варте:
    фотографія передає і те, і те."""
    дж = джерела_інтересу(E)
    if not дж:
        return []                          # порожнечу вже називає K-INT-04
    лише_фактура = [d for d in дж if all(в.startswith("фактура") for в in d["важелі"])]
    if len(лише_фактура) != len(дж):
        return []
    return [dict(_зн(
        "K-CRA-10", "hint",
        "увесь інтерес образу — фактурний, а рендер приміряння це з'їдає",
        [d["річ"] for d in лише_фактура],
        "джерел інтересу %d, і всі до одного фактурні (%s). Фотографія просить "
        "більше контрасту, більше структури й гострішого силуету; фактурний "
        "контраст на ній зникає майже цілком — а наш рендер і Є фотографія"
        % (len(дж), "; ".join(", ".join(d["важелі"]) for d in лише_фактура[:3])),
        ремонт=["для рендера — додати одне НЕфактурне джерело: акцентний колір або "
                "чіткіший край силуету; у житті образ працює як є"],
        ламається="це зміщення НАШОГО каналу, не вада образу: правило знає лише "
                  "напрям («фактура на фото слабшає»), а не величину — окремого "
                  "режиму оцінки «для камери» в системі нема",
        поріг=0.0, вимір=float(len(лише_фактура)), повна=2.0))]


def ремесло(речі, E, команди=(), intent="conventional"):
    """Сім'я K-CRA над зібраним образом: (знахідки). Один вхід — один викликач.

    `команди` — команди розкладки цього образу (`outer.команди_укладки` +
    `outer.ремонти`): вхід K-CRA-03. Порожньо — правило мовчить, як і має."""
    зн = (третя_річ(речі) + фокуси(E, intent) + жести(команди)
          + глибина_шарів(речі, E) + камера_проти_життя(E))
    return [z for z in обмежити_вагу(зн) if not z.pop("під_підлогою", False)]


