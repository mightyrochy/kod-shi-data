# ⚠ СИЛА hard ТУТ ЗАКОННА, ПОПРИ «сила ≤ верифікація»: це не емпіричне твердження про
# світ, яке треба доводити, а ПРИНЦИП — межа, яку встановила людина. Верифікувати
# нічого: доказом є те, що людина це сказала. Саме тому корпус позначає його
# «принцип·hard», а не «C·strong».
ЗОНИ_ПОКРИТТЯ = ("руки", "плечі", "декольте", "спина", "ноги", "живіт", "коліна")

def вето_покриття(E, вето=None, тіло=None):
    """K-PC-08. Речі, що порушують особисте вето покриття. Абсолютний фільтр.

    `вето`: {"зони": ["декольте","спина"], "ноги_вище_см": 45} — «ноги_вище_см»
    міряється ВІД ПІДЛОГИ (як і всі краї в посадка.py), тобто «поділ не вище N см
    від підлоги». Потребує `тіло` для перерахунку, коли поріг заданий від коліна.

    Повертає (чисті, знахідки). Знахідка — гейт: річ ПРИБИРАЄТЬСЯ, не понижується."""
    if not вето: return list(E), []
    зони = {str(z).strip().lower() for z in (вето.get("зони") or [])}
    поріг = вето.get("ноги_вище_см")
    чисті, зн = [], []
    for e in E:
        # ВЕТО ЧИТАЄ ВИВЕДЕНІ ЗОНИ, не лише заявлене поле. Доти воно спиралось на
        # `відкрита_зона`, яке НІХТО НЕ ПИСАВ — тобто правило сили `hard` на реальному
        # каталозі мовчало б завжди. Тепер зона виводиться з `виріз`, `тип`, назви й
        # геометрії краю (див. `зони_речі`).
        мої, чому_зон = зони_речі(e, тіло=тіло)
        перетин = sorted(мої & зони)
        # `коротко` — та сама гілка, що й `якщо`, але без чисел і без переліку
        # доказів: рівно те, що влазить у рядок промпту (див. блок нижче).
        якщо = коротко = None
        if перетин:
            якщо = ("відкриває %s, яку людина не відкриває (%s)"
                    % ("зону «%s»" % перетин[0] if len(перетин) == 1
                       else "зони %s" % ", ".join("«%s»" % z for z in перетин),
                       "; ".join(чому_зон)))
            коротко = ("відкриває %s — %s особистого вето, замінити"
                       % (", ".join("«%s»" % z for z in перетин),
                          "зону" if len(перетин) == 1 else "зони"))
        elif поріг is not None and e.get("низ_см") is not None \
                and e.get("слот") in ("низ", "сукня", "комплект"):
            if float(e["низ_см"]) > float(поріг):
                якщо = ("поділ на %.0f см від підлоги — вище особистої межі %.0f см"
                        % (float(e["низ_см"]), float(поріг)))
                коротко = "поділ вище особистої межі покриття — замінити на довше"
        if якщо is None:
            чисті.append(e); continue
        # ── ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026) ────────────────
        # before: «„Спідниця класична“ порушує вето покриття» — найсильніша сила
        # системи (hard, гейт) і при цьому речення, з якого не видно, ЩО саме в
        # речі порушує межу. А порушень тут два різні: відкрита зона й задовгий
        # поділ, — і ремонт у них різний. Все конкретне лежало в `чому` й `ремонт`,
        # тобто в полях, яких промпт ремонту не друкує; ші бачила вирок без складу.
        # after (два справжні рядки з двох прогонів):
        #   · «топ з відкритим вирізом»: відкриває «декольте» — зону особистого
        #     вето, замінити [1.00]
        #   · «спідниця міні»: поділ вище особистої межі покриття — замінити
        #     на довше [1.00]
        # Гілка не міняється: `коротко` заповнюється в тій самій розвилці, що й
        # `якщо`; ні порогу, ні сантиметрів у речення не пішло.
        зн.append(dict(_зн(
            "K-PC-08", "hard",
            "«%s»: %s" % (e.get("річ", e.get("id")), коротко),
            [e.get("річ") or e.get("id")],
            якщо + ". Це особиста межа, а не оцінка речі: обґрунтування не потрібне, "
                   "і система не пропонує спробувати",
            ремонт=["інша річ, що не відкриває цю зону"],
            запит=dict(слот=e.get("слот"), замість=e.get("річ"),
                       не_відкривати=sorted(зони) or None,
                       поділ_не_вище_см=поріг,
                       чому="K-PC-08: особисте вето покриття"),
            ламається="вето читає поле `відкрита_зона` і геометрію краю. Річ, яка "
                      "відкриває зону, але поля не несе, ПРОЙДЕ — це діра у ВХОДІ, "
                      "не в правилі, і вона видна в `без_поля_зони`"),
            регістр="гейт", блокує=True, сила_нп=1.0,
            сила_нп_джерело="принцип (не вимір): межу встановила людина"))
    return чисті, зн

def покриття_без_поля(E, тіло=None):
    """Скільки речей не дають ЖОДНОЇ підстави судити про зони — ні заявленої, ні
    виведеної. Це роздільна здатність K-PC-08, і вона мусить бути видною.

    ⚠ «Без підстав» ≠ «нічого не відкриває»: штани нічого не відкривають законно, а
    сукня без полів `виріз`/`назва` мовчить із незнання. Розрізнити їх можна лише за
    слотом, тому обидва числа повертаються окремо."""
    ризикові = ("верх", "сукня", "комплект", "низ", "верхній_шар")
    без, безпечні = [], []
    for e in E:
        з, чому = зони_речі(e, тіло=тіло)
        if з or чому: continue
        (без if e.get("слот") in ризикові else безпечні).append(
            e.get("річ") or e.get("id"))
    return dict(усього=len(E), без_підстав=len(без), приклади=без[:5],
                поза_ризиком=len(безпечні),
                чому="річ у слоті, що МОЖЕ відкривати зону, але без жодного поля, з "
                     "якого це виводиться (`виріз`, тип/назва, `низ_см`), проходить "
                     "вето мовчки. Частка таких і є стеля надійності K-PC-08")


