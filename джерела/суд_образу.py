def тканина_проти_крою(E, розрив_макс=2.0):
    """K-MAT-01. Річ, у якій тканина й крій тягнуть у різні боки формальності."""
    зн = []
    for e in одна_на_річ(E):
        т = str(e.get("текстура") or "").strip().lower()
        тк = ТКАНИНА_ФОРМАЛЬНІСТЬ.get(т)
        # ВИПРАВЛЕНО ПІСЛЯ ПРОБИ: спершу тут стояв `інтервал_формальності(e)`, і
        # правило МОВЧАЛО на атласних спортивних штанях — бо полярність тканини вже
        # зсунула той інтервал угору (спортивний 1–3 + satin +1 + «атласн» +1 = 1–5),
        # тобто суперечність УЖЕ була усереднена в те саме число, з яким її порівнюють.
        # Правило міряло б власну поправку. Порівнювати треба з БАЗОВИМ інтервалом
        # ТИПУ — тим, що каже крій сам по собі, без тканини.
        кр_lo, кр_hi, _ = інтервал_типу(e.get("тип"))
        if not тк or кр_lo is None: continue
        # розрив = зазор між інтервалами, що дивляться один на одного
        розрив = max(0.0, тк[0] - кр_hi, кр_lo - тк[1])
