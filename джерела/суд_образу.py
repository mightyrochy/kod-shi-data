        # `джерело_площі` називає, звідки вона («піксель», «геометрія», «маски»).
        # Наслідок чесний і незручний: поки фід не дає ні площ, ні довжин, п'ять
        # колірних правил утримуються й кажуть це вголос — рівно те, для чого
        # `_утримано_без_площ` і написана.
        площі_є = all(e["площа"] is not None and e.get("джерело_площі") for e in E)
