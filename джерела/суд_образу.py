        # бракує, — це та сама тиша, тільки з алібі (той самий принцип, що в
        # `accessory.БЕЗ_ВХОДУ`).
        if стан == "без входу":
            п["бракує"] = _ЯКОГО_ПОЛЯ.get(вхід, вхід)
