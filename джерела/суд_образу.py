    if розкид_каталогу:
        for r in речі:
            r.setdefault("розкид", розкид_каталогу)
    н = _намір(intent)
    рез = dict(особа=особа, намір=intent, схема=схема,
               намір_відомий=_канон_намір(intent) in INTENT, стани={})
    if not рез["намір_відомий"]: рез["попередження_наміру"] = н["підпис"]
    _стани_E = {}
    # ── ВІДСТАНЬ ОГЛЯДУ ВИВОДИТЬСЯ ТУТ, ОДИН РАЗ НА ОБРАЗ (K-COND-04) ─────────
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ. Вага слота була одна на всі сцени, і правила, які на
    # неї множаться, судили сережки за столом і сережки на весільному фото
    # однаково. Тепер `місце`+`формат`+`нагода` дають вісь, а вісь — вагу; на
    # «розмові» приобличчеві слоти важчають (сережки, шарф, комір судяться
    # суворіше, взуття м'якше), на «повний зріст» навпаки.
    # ЧОМУ ТУТ, А НЕ В КОЖНОМУ ПРАВИЛІ: вага входить у `елементи()` полем `near`,
    # і правила (K-CRA-07, K-COL-06-M, а через нього K-CLR-05) читають те саме
    # поле, що й читали. Жодне з них про сцену не знає й знати не мусить.
    # ПРИ None ПОВЕДІНКА ТА САМА, ЩО ДО ПРАВКИ, і це видно в `рез["дистанція"]`
    # разом із причиною — мовчання тут заборонене так само, як у знахідках.
    _дист = _ДИСТ.з_сценарію(dict(місце=місце, формат=формат, нагода=нагода))
    рез["дистанція"] = _дист
    for st in стани(речі):
        E = елементи(речі, st, дистанція=_дист.get("дистанція"))
        _стани_E[st] = E
        # ── СВІДКОМ ПЛОЩІ Є ЇЇ ПОХОДЖЕННЯ, А НЕ НАЯВНІСТЬ ЧИСЛА (08.09.2026) ──
        # ЩО ТУТ СТОЯЛО: `all(e["площа"] is not None …)`. Свідком узято сам факт,
        # що в полі щось лежить. Але на живому шляху `composer._у_річ` кладе
