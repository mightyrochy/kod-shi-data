    спідниці = [р for р in речі
                if р.get("слот") == "низ" and str(р.get("тип") or "") == "спідниця"]
    if not спідниці:
        return зн
    взуття = [р for р in речі if р.get("слот") == "взуття"]
    каблуки = [float(р["каблук_см"]) for р in взуття if р.get("каблук_см") is not None]
    каблук = max(каблуки) if каблуки else None      # None = картка мовчить, не «0 см»
