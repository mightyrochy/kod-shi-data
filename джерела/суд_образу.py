    особа = контраст_особи(F, source)
    if масштаб_особи is None and зріст_см is not None:
        # зріст з онбордингу -> масштаб особи (profile.масштаб, якорі ДСТУ + Держстат)
        try:
            import profile as _pr
            _м = _pr.масштаб(зріст_см)
            масштаб_особи = _м.get("масштаб_особи")
            рез_надійність = _м.get("надійність")
        except Exception:
            масштаб_особи, рез_надійність = None, None
    else:
        рез_надійність = None
    if розкид_каталогу:
        for r in речі:
            r.setdefault("розкид", розкид_каталогу)
    н = _намір(intent)
    рез = dict(особа=особа, намір=intent, схема=схема,
               намір_відомий=_канон_намір(intent) in INTENT, стани={})
    if not рез["намір_відомий"]: рез["попередження_наміру"] = н["підпис"]
    _стани_E = {}
    # ── ВІДСТАНЬ ОГЛЯДУ ВИВОДИТЬСЯ ТУТ, ОДИН РАЗ НА ОБРАЗ (K-COND-04) ─────────
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ. Вага слота була одна на всі сцени, і правила, які на
    # неї множаться, судили сережки за столом і сережки на весільному фото
    # однаково. Тепер `місце`+`формат`+`нагода` дають вісь, а вісь — вагу; на
    # «розмові» приобличчеві слоти важчають (сережки, шарф, комір судяться
    # суворіше, взуття м'якше), на «повний зріст» навпаки.
    # ЧОМУ ТУТ, А НЕ В КОЖНОМУ ПРАВИЛІ: вага входить у `елементи()` полем `near`,
    # і правила (K-CRA-07, K-COL-06-M, а через нього K-CLR-05) читають те саме
    # поле, що й читали. Жодне з них про сцену не знає й знати не мусить.
    # ПРИ None ПОВЕДІНКА ТА САМА, ЩО ДО ПРАВКИ, і це видно в `рез["дистанція"]`
    # разом із причиною — мовчання тут заборонене так само, як у знахідках.
    _дист = _ДИСТ.з_сценарію(dict(місце=місце, формат=формат, нагода=нагода))
    рез["дистанція"] = _дист
    for st in стани(речі):
        E = елементи(речі, st, дистанція=_дист.get("дистанція"))
        _стани_E[st] = E
        # ── СВІДКОМ ПЛОЩІ Є ЇЇ ПОХОДЖЕННЯ, А НЕ НАЯВНІСТЬ ЧИСЛА (08.09.2026) ──
        # ЩО ТУТ СТОЯЛО: `all(e["площа"] is not None …)`. Свідком узято сам факт,
        # що в полі щось лежить. Але на живому шляху `composer._у_річ` кладе
        # `площа=r.get("площа", 1.0/3)` КОЖНІЙ речі, а покриття поля `площа` у фіді
        # — 0 %. Тобто заглушку дістають усі, `елементи()` нормує її до 1/N, і
        # `площа is not None` завжди True. `_утримано_без_площ` не виносилось
        # НІКОЛИ, і п'ять правил судили над рівномірною константою — при тому, що
        # в тому самому словнику поруч стояло `походження_площ: "не виміряно"`.
        #
        # ВИМІРЯНО 08.09.2026 на одному образі з шести речей (блуза, штани, човники,
        # сережки, шарф, брошка), два прогони — заглушка проти масок:
        #   заглушка 1/6 → K-COL-01, K-COL-02, K-COMP-03   (жодного «утримано»)
        #   маски        → K-COL-05                        (єдина правдива)
        # Заглушка ОДНОЧАСНО додала три хибні знахідки (дрібні сережки й брошка
        # перевалили `min_area` 0.03 і поріг конфлікту 0.10, бо 1/6 = 0.167) і
        # проковтнула справжню (два сироти-акценти на реальних 0.005 і 0.007).
        # Це не «трохи неточно» — це вигадка в обидва боки.
        #
        # Тепер свідок — ПОХОДЖЕННЯ: площа рахується виміряною лише тоді, коли
        # `джерело_площі` називає, звідки вона («піксель», «геометрія», «маски»).
        # Наслідок чесний і незручний: поки фід не дає ні площ, ні довжин, п'ять
        # колірних правил утримуються й кажуть це вголос — рівно те, для чого
        # `_утримано_без_площ` і написана.
        площі_є = all(e["площа"] is not None and e.get("джерело_площі") for e in E)
        зн = (перевірка_сегментації(F, E) + біля_обличчя(E, особа) +
              білі(E, source) + принти(речі, E) +
              _придатність_принтів(F, речі, E, source, масштаб_особи, зона_камуфляж,
                                   рез_надійність) +
              температура_нейтралі(E, F, source, драп, мета, intent, речі) +
              бік_b_біля_обличчя(E, F, речі, intent, мета) +      # R-COL-16
              метали(E, F, source, драп, intent, речі) +
              блиск_бюджет(E, intent, нагода) +
              розмір_не_посадка(речі, E) +
              свідки_крою(речі, E) +
              нагода_палітра(E, нагода, дрес_код, фото, траур) +
              намір_доречності(формальність_образу(E, сцен, bool((сцен or {}).get("вечір"))), intent) +
              намір_комфорту(речі, intent) +
              погода(E, темп_c, опади, вітер, сонце, st, речі=речі))
        _утримання_площ = None
        if площі_є:
            зн = (перевірка_value(E, intent) + зн + бюджет_хроми(E, F, intent) +
                  сім_ї_образу(E, intent) + відлуння(E, фокус, intent, схема) + нейтралі_крос(E))
        else:
            _утримання_площ = _утримано_без_площ(E)
            зн = [_утримання_площ] + зн
        зн = обмежити_слабшу_вісь(зн, source)   # R-PC-03: поки вісь СПРАВДІ слабша
        зн = зн + несумісні_ремонти(зн)     # аудит консистентності -> явна знахідка
        # ІНВАРІАНТ ДЛЯ ВСІХ ЗНАХІДОК СТАНУ, А НЕ ЛИШЕ ДЛЯ ТИХ, ХТО ПРОЙШОВ ГЕЙТ
        # НАМІРОМ (Н-outfit-1-080): вага ≤ стелі категорії, слово = категорії.
        # Функція ідемпотентна (ріже ДО стелі), тож повторне застосування після
        # composer нічого не зрізає двічі — зафіксовано тестом у розділах гейтів §75.
        # ── ПІДЛОГА СИЛИ, ОДИН РАЗ І НА ВИХОДІ (Н-outfit-1-089) ──────────
        # Доти цю перевірку тримали 11 розсипаних `continue` у гілках емісії, і
        # реєстр обіцяв її «в усіх гілках» — обіцянка, яку нічим перевірити.
        # Тепер гілки емісії підлоги не знають, а відсів стоїть тут, після
        # `обмежити_вагу`: зрізання до стелі категорії може САМЕ й опустити вагу
        # під підлогу, тож порядок «спершу зрізати, тоді відсіяти» обов'язковий.
        зн = [z for z in обмежити_вагу(зн) if not z.pop("під_підлогою", False)]
        джерела = {e.get("джерело_площі") for e in E if e["площа"] is not None}
        не_виміряний_near = sorted({e["річ"] for e in E if not e.get("near_виміряний")})
        рез["стани"][st] = dict(
            елементи=[dict(річ=e["річ"], слот=e["слот"], L=e["L"], C=e["C"],
                           сім_я=e["сім_я"], площа=e["площа"]) for e in E],
            # ── `None` І «НЕ ПОМІРЯНО» — РІЗНІ СТАНИ (Н-outfit-1-081) ────────
            # Тут стояло `else None`, і викличник читав це як «структури нема»
            # (образ плоский, один рівень світлоти) — тобто як ВИСНОВОК. Насправді
            # це «не поміряно»: площ нема, і структура світлоти не обчислювалась
            # узагалі. Два різні стани під одним значенням — саме той мовчазний
            # хибний вердикт, якого модуль не дозволяє собі у знахідках.
            структура=(value_структура(E) if площі_є else
                       dict(утримано=True,
                            чому="структура світлоти не обчислювалась: площі не виміряні "
                                 "(див. знахідку «площа» — вона несе покриття входу)",
                            покриття_входу=(_утримання_площ or {}).get("покриття_входу"))),
            знахідки=зн,
            походження_площ=sorted(x for x in джерела if x) or "не виміряно",
            near_не_виміряний=не_виміряний_near or None,
            # БЛОКЕРИ — тільки те, що має право зупинити образ: гейти на вимірі.
            # Усе на T3-конвенції з блокерів прибрано — воно тепер у репліках.
            блокери=[z for z in зн if z.get("блокує") and z.get("сила") in ("hard", "strong")],
            # РЕПЛІКИ — спостереження для стиліста-моделі, не зупиняють нічого.
            репліки=[dict(правило=z["правило"], впевненість=z.get("впевненість"),
                          текст=z.get("для_стиліста"), речі=z.get("речі"),
                          варіант=z.get("ремонт"))
                     for z in зн if z.get("регістр") == "репліка"],
            питання=[dict(правило=z["правило"], текст=z.get("питання_людині"),
                          навіщо=z.get("навіщо"))
                     for z in зн if z.get("сила") == "питання"],
            запити=[z["запит_у_каталог"] for z in зн if z.get("запит_у_каталог")])
    # K-WEA-02 — КРОС-СТАННЕ: рахується після циклу, бо порівнює стани між собою.
    # Знахідка кладеться у стан «надворі»: саме там проблема й видима.
    for z in пальто_це_образ(_стани_E, темп_c):
        if "надворі" in рез.get("стани", {}):
            рез["стани"]["надворі"]["знахідки"].append(z)
    рез["не_зроблено"] = не_зроблено()
    # виведений сценарій їде в результат: ші-стиліст мусить бачити ЦІЛЬ (діапазон
    # формальності, поставу ризику, вето, погодний шар), а не лише знахідки проти неї
    рез["сценарій"] = сцен
    рез["як_читати"] = (
        "блокери зупиняють образ і стоять лише на вимірі (крок світлоти, видима різниця "
        "нейтралей). репліки — спостереження для композитора з мірою впевненості, вони "
        "нічого не забороняють: рішення за моделлю. це навмисно: рулбук не доведений як "
        "суддя (перевірити нічим), а приобличчевий контраст — виміряно слабкий сигнал, "
        "тож він промовляється, а не карає.")
    return рез

