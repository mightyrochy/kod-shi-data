# Тому це окрема секція над образом, і кличе її `pipeline.перевірити_образ` один
# раз, поруч із кроком редагування.
#
# ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after, виміряно на `каталог_повний` 17.09.2026):
#   before — п'ять правил сім'ї не давали ЖОДНОГО рядка у вердикті; пункти
#            чекліста надлишку 2, 8 і 10 стояли «пройдено» на будь-якому образі,
