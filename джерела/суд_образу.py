    def друк(назва, F, речі, source="uncontrolled", фокус=None, intent="conventional"):
        """Проганяє `review` на одному образі й друкує вердикт: особу, площі по станах,
        знахідки з ремонтом і запити в каталог — так суд видно очима."""
        r = review(F, речі, source, фокус, intent)
        print(f"\n{'='*76}\n{назва}")
        о = r["особа"]
        print(f"особа: L*шкіри={о['L_шкіри']} L*волосся={о['L_волосся']} "
              f"контраст={о['value_gap']} ({о['рівень']})")
        for st, d in r["стани"].items():
            площі = ", ".join(f"{e['річ']} {e['площа']}" for e in d["елементи"]
                              if e["площа"] is not None)
            print(f"\n  [{st}] площі ({d['походження_площ']}): {площі or '—'}")
            for z in d["знахідки"]:
                if z.get("сила") == "ok":
                    print(f"    ok      {z['правило']}: розрив {z['найбільший_розрив']} "
                          f"проти {z['контраст_особи']} — у межах")
                    continue
                print(f"    {z['сила']:9s} {z['правило']}: {z['суть'][:78]}")
                if z.get("утримані_правила"):
                    print(f"              утримано: {len(z['утримані_правила'])} правил")
                if z.get("ремонт"):
                    rem = z["ремонт"] if isinstance(z["ремонт"], str) else z["ремонт"][0]
                    print(f"              ремонт: {rem[:86]}")
            if d["запити"]: print(f"    -> запити в каталог: {d['запити']}")

