        тк = ТКАНИНА_ФОРМАЛЬНІСТЬ.get(т)
        # ВИПРАВЛЕНО ПІСЛЯ ПРОБИ: спершу тут стояв `інтервал_формальності(e)`, і
        # правило МОВЧАЛО на атласних спортивних штанях — бо полярність тканини вже
        # зсунула той інтервал угору (спортивний 1–3 + satin +1 + «атласн» +1 = 1–5),
