        _СЛ.запис("K-SYS-08", "стеля надлишку: %(провал)d провал / %(пройдено)d пройдено / %(без входу)d без входу"
                  % підсумок["надлишок"], "чеклісти", значення=str(підсумок["надлишок"]), сила=None, напрям="чекліст")
