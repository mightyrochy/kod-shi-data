# Слоти, які рахуються ТРЕТЬОЮ РІЧЧЮ (K-CRA-01). Список — із самого брифа
# (`brief.ПРАВИЛО_РЯДКА["третя_річ"]`): «верх+низ = одягнена; +1 шар або сильний
# аксесуар = стилізована». Тобто третя річ — це ШАР або АКСЕСУАР, а не будь-яка
# третя позиція в образі.
# ЧОМУ ВЗУТТЯ Й СУМКА СЮДИ НЕ ВХОДЯТЬ, І ЦЕ РІШЕННЯ, А НЕ НЕДОГЛЯД: обидва є
# в кожному образі за побудовою (`_живі_слоти` стенда дають взуття й сумку
# завжди), тож зарахувати їх означало б зробити правило тривіально істинним —
