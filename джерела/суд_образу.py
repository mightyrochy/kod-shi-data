        if розрив <= розрив_макс: continue
        сила_нп = round(min(1.0, (розрив - розрив_макс) / 3.0), 2)
        # ── ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026) ────────────────
        # before: «у „худі атласне“ тканина й крій тягнуть у різні боки» — той самий
        # рядок і на атласному худі (тканина формальніша за крій), і на джинсовому
        # костюмі (крій формальніший за тканину). «У різні боки» — це і є пропуск
        # боку: обидві заміни звучать однаково, а вони протилежні. Який кінець
        # тягнути, знав `ремонт` («та сама річ у тканині рівня …»), і саме він до
        # промпту ші не доїжджає.
