def чеклісти(знахідки, E, intent="conventional"):
    """K-SYS-08 / K-SYS-09 пункт за пунктом. Повертає dict(надлишок=[…], прісність=[…],
    підсумок=…). Жодного числа якості — лише стан кожного пункту (R-ABC-08)."""
    за_правилом = {}
    for z in знахідки:
        if not isinstance(z, dict) or not z.get("правило"): continue
        if z.get("сила") in ("питання", "утримано"): continue
        if _під_підлогою(z.get("сила_нп")) and not z.get("блокує"): continue
        за_правилом.setdefault(z["правило"], []).append(z)
    def пункт(ід, назва, правила, вхід):
        зн = [z for r in правила for z in за_правилом.get(r, [])]
        if зн:
            стан = "провал"
        elif not правила or not _вхід_є(вхід, E, знахідки):
            стан = "без входу"
        else:
            стан = "пройдено"
        return dict(пункт=ід, що=назва, правила=list(правила), стан=стан, вхід=вхід,
                    знахідки=[(z.get("правило"), z.get("суть")) for z in зн][:3])
    над = [пункт(*p) for p in ЧЕКЛІСТ_НАДЛИШКУ]
    Р = одна_на_річ(E)
    прс = [пункт(*p) for p in ЧЕКЛІСТ_ПРІСНОСТІ]
    # B3 і B4 рахуються прямо: вони не мають правила-емітента
    гучних = [e for e in Р if not e.get("нейтраль") and lch(tuple(e["lab"]))[1] >= ІНТЕРЕС_C_МІН] if all(e.get("lab") for e in Р) else []
    for p in прс:
        if p["пункт"] == "B3":
            p["стан"] = "провал" if len(гучних) <= 1 and not any(e.get("візерунок") not in (None, "", "solid") for e in Р) else "пройдено"
            p["що"] += " (нейтралі + ≤1 акцент і жодного принту = дефолт)"
        if p["пункт"] == "B4":
            if _вхід_є("текстура", E, знахідки):
                p["стан"] = "пройдено" if len({e.get("текстура") for e in Р if e.get("текстура")}) >= 2 else "провал"
    підсумок = dict(
        надлишок={с: sum(1 for p in над if p["стан"] == с) for с in ("провал", "пройдено", "без входу")},
        прісність={с: sum(1 for p in прс if p["стан"] == с) for с in ("провал", "пройдено", "без входу")})
    try:
        import trace as _СЛ
        _СЛ.запис("K-SYS-08", "стеля надлишку: %(провал)d провал / %(пройдено)d пройдено / %(без входу)d без входу"
                  % підсумок["надлишок"], "чеклісти", значення=str(підсумок["надлишок"]), сила=None, напрям="чекліст")
        _СЛ.запис("K-SYS-09", "підлога прісності: %(провал)d провал / %(пройдено)d пройдено / %(без входу)d без входу"
                  % підсумок["прісність"], "чеклісти", значення=str(підсумок["прісність"]), сила=None, напрям="чекліст")
    except Exception:
        pass
