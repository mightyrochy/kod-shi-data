# нагоди річ занадто ошатна» за смугою 3–4 — два вердикти коду про ОДНУ річ в
# одному прогоні.
# ЩО ТЕПЕР. Смуга рахується тут, з УСІХ полів сценарію, один раз і однаково для
# всіх трьох читачів. Порядок джерел не міняється: слова людини (`ошатність`)
# переважають таблицю, як і доти (K-KOH-05).
# Ключ, під яким шов кладе пораховану смугу в сам сценарій (`міст_пакет`,
# `міст_відповіді`): далі по шляху кожен читач бере ДВА ЧИСЛА, а не рахує свої.
# Без штампа одна й та сама сцена дає різну смугу тим читачам, до яких доїхало
# менше полів (композитор бачив сцену без години — 4–6, суд її речі без місця — 3–4).
ШТАМП_СМУГИ = "_смуга_ошатності"

def смуга_ошатності(сцен):
    """(lo, hi, звідки) — ОДНА смуга ошатності сценарію для всіх читачів коду.

    `сцен` — нагода в полях `сценарій.ПОЛЯ` (плюс службові `_ошатність`, `темп_c`).
    Джерело одне — число мовної моделі (`ошатність` / `_ошатність` = [від, до]) або штамп
    прогону з нього, зведене до смуги одного щабля (`один_щабель`, рядок 8970): пара через два щаблі —
    звідки б не прийшла (паспорт, плитка, збережений випадок) — пул, суд і бриф щаблем не стає.
    Числа нема → None: «нічого не чіпаємо» лишається названим.
    """
    с = dict(сцен or {})
    for ключ in (ШТАМП_СМУГИ, "ошатність", "_ошатність"):
        о = с.get(ключ)
        if isinstance(о, (list, tuple)) and len(о) == 2:
            try:
                a, b = float(о[0]), float(о[1])
            except (TypeError, ValueError):
                continue
            lo, hi = смуга_щабля(один_щабель(a, b))
            return lo, hi, "ошатність зі слів"
    # НП-в крок 2 (принцип власника 01.10: «код має знати те, що може точно порахувати»):
    # смуга — ЛИШЕ число мовної моделі. Доти без нього смугу давала таблиця (пресет нагоди,
    # місце, дрес-код, а без них — «широкий дефолт 3–6»), і пул чистився за смугою, якої
    # ніхто не казав. Числа нема → None: смуги нема, відсіву нема.
    return None


