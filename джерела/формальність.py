ПОЛЯРНОСТІ_ФОРМАЛЬНОСТІ = {
 # ознака речі -> (зсув низу, зсув верху)
 "текстура": {"smooth_shine": (0, +1), "satin": (0, +1), "silk_shine": (0, +1),
              "smooth_matte": (0, 0), "leather": (0, 0), "tweed_boucle": (0, +1),
              "knit_fine": (0, 0), "knit_chunky": (-1, 0), "denim": (-1, 0)},
}

def інтервал_формальності(e):
    """(лоу, хай) формальності ЕЛЕМЕНТА: інтервал типу, зсунутий полярностями речі.

    ЩО ЦЕ МІНЯЄ (before/after): формальність була ТОЧКОЮ з таблиці типів, і розкид
    точок таврував high-low (блуза+джинси+човники) — головний хибний спрацьовувач,
    який міряє `аудит_формальності`. Тепер перекриття інтервалів робить high-low законним без
    окремого винятку. Зсув дає лише код текстури; слова матеріалу й назви — ні (рядок 5194).

    Повертає (None, None), коли типу нема: шар мовчить, а не вигадує середину."""
    тип = e.get("тип")
    лоу, хай, _ = інтервал_типу(тип)
    # рядок 1412: смуга сукні без уточнення — з бала фото; без бала й модифікатора — без входу
    ф = _бал_фото(e) if тип in ТИПИ_СМУГА_З_ФОТО else None
    if ф is not None:
        лоу, хай = max(1, ф - ФОТО_ПІВКРОК), min(10, ф + ФОТО_ПІВКРОК)
    elif смуга_з_фото_без_входу(e):
        return (None, None)
    if лоу is None:
        # фолбек на явно заявлену формальність речі, якщо вона є
        f = e.get("формальність")
        return (float(f), float(f)) if f is not None else (None, None)
    # ── ПЕРЕТИН З МОДИФІКАТОРОМ (рядок 184, повернення куратора 24.09.2026) ──
    # Поки `фід_слот` брав тип із ПЕРШОГО ключа словника, прикметник «джинсова»,
    # «трикотажна», «спортивні» БУВ типом — і тим тримав казуальність речі.
    # Щойно тип став іменником, стеля піднялась: 346 із 607 речей, що змінили
    # тип, дістали стелю вищу на ≥ 2 (трикотажна сукня 5 → 9, джинсова спідниця
    # 4 → 7, джогери 3 → 7), і K-KOH-05 «рівень образу нижче» замовкав на
    # джинсовій сукні на весіллі 7–9.
    # Слово не зникло — воно МОДИФІКАТОР (`фід_слот.тип_модифікатор`), і його
    # інтервал теж правда про річ. Тому беремо ПЕРЕТИН, а не заміну: для вета й
    # бажання річ лишається сукнею, для формальності — сукнею з деніму.
    #   сукня 3–9 ∩ джинси 2–4 = 3–4;  штани 3–7 ∩ спортивний 1–3 = 3;
    #   сукня 3–9 ∩ сорочка 4–6 = 4–6; спідниця 3–7 ∩ шорти 1–4 = 3–4.
    # Нових чисел не заводиться: обидва інтервали вже є в `ТИП_ІНТЕРВАЛ`.
    мод = e.get("тип_модифікатор")
    if мод and мод != тип:
        м_лоу, м_хай, _ = інтервал_типу(мод)
        if м_лоу is not None:
            нл, нх = max(лоу, м_лоу), min(хай, м_хай)
            # ПОРОЖНІЙ ПЕРЕТИН — БЕРЕТЬСЯ ІНТЕРВАЛ МОДИФІКАТОРА, і це названо:
            # два слова кажуть про різні смуги, і вужче — те, що каже матеріал
            # чи крій самої речі, а не родове слово.
            лоу, хай = (нл, нх) if нл <= нх else (м_лоу, м_хай)
    if ф is not None:
        # бал фото вже бачив тканину й оздоблення: полярності не додаються (рядок 1412)
        return (float(лоу), float(хай))
    d_лоу = d_хай = 0
    for поле, мапа in ПОЛЯРНОСТІ_ФОРМАЛЬНОСТІ.items():
        # Походження зі слів назви не стає виміром ошатності через код текстури.
        if поле == "текстура" and e.get("тканина_за_чим"):
            continue
        v = str(e.get(поле) or "").strip().lower().replace("-", "_")
        if v in мапа:
            a, b = мапа[v]; d_лоу += a; d_хай += b
    return (float(max(1, лоу + d_лоу)), float(min(10, хай + d_хай)))

