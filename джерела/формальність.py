    тип = e.get("тип")
    лоу, хай, _ = інтервал_типу(тип)
    if лоу is None:
        # фолбек на явно заявлену формальність речі, якщо вона є
        f = e.get("формальність")
        return (float(f), float(f)) if f is not None else (None, None)
