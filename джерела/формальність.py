# БЕЗ БАЛА — БЕЗ ВХОДУ, НЕ 3–9 (аудит/ПРОДУКТ.md п.4). Нема ні бала, ні модифікатора — (None, None): шар
# мовчить про цю річ, а `формальність_образу` ставить запис «без входу» з названим полем
# `формальність_фото`, і пункт 5 чекліста надлишку стає «без входу», а не «пройдено».
ТИПИ_СМУГА_З_ФОТО = ("сукня_без_уточнення",)
ФОТО_ПІВКРОК = 1


def _бал_фото(e):
    """`формальність_фото` речі числом або None (нема, не число, булеве)."""
    ф = e.get("формальність_фото")
    return ф if isinstance(ф, (int, float)) and not isinstance(ф, bool) else None


def смуга_з_фото_без_входу(e):
    """Чи річ — тип зі смугою з фото (`ТИПИ_СМУГА_З_ФОТО`), у якої смуги нема: ні бала фото,
    ні модифікатора назви з власною смугою. Таку річ шар формальності не судить (рядок 1412)."""
    if e.get("тип") not in ТИПИ_СМУГА_З_ФОТО or _бал_фото(e) is not None:
        return False
    мод = e.get("тип_модифікатор")
    return not (мод and мод != e.get("тип") and інтервал_типу(мод)[0] is not None)


def інтервал_типу(тип):
    """(лоу, хай, чому). Формальність типу як ІНТЕРВАЛ (K-KOH-05).
    Невідомий тип -> (None, None, чому): шар мовчить, а не вигадує середину."""
    if not тип:
        return None, None, ("типу нема — формальність не виводиться. Правило шару "
                            "коherentності (K-KOH-02/05) мовчить, і це видно")
    i = ТИП_ІНТЕРВАЛ.get(тип)
    if not i:
        return None, None, "тип «%s» невідомий шару формальності" % тип
    return i[0], i[1], ("тип «%s» → формальність %d–%d. Інтервал, не точка: шовкова "
                        "блуза й бавовняна — один тип, різні формальності (K-KOH-05)"
                        % (тип, i[0], i[1]))

def типи_нижче_межі(межа):
    """Типове вето за верхнім краєм відомого інтервалу, без точкових оцінок сумок.

    Вироджена точка з колишнього фолбеку не задає виміряної стелі типу;
    злиття таблиць не додає нею нового жорсткого вето casual.
    """
    return {т for т, (низ, верх) in ТИП_ІНТЕРВАЛ.items() if низ < верх <= межа}


