def _кроки(n):
    """Зсув словами: «0,5 кроку», «1 крок», «2 кроки», «5 кроків». Доти `%.0f кроків` писав 0,5 як
    «на 0 кроків» — ремонт, що не просить нічого (рядок 6754)."""
    n = round(float(n), 1)
    if n != int(n):
        return ("%.1f" % n).replace(".", ",") + " кроку"
    n = int(n)
    return "%d %s" % (n, "крок" if n % 10 == 1 and n % 100 != 11
                      else "кроки" if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14 else "кроків")

