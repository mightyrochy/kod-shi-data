# -*- coding: utf-8 -*-
"""Тест записів `похибка_вимірів_тіла`: повнота імен, поля запису, виведення числа з джерела, читання.

Прогін: `python3 тест_похибки_вимірів_тіла.py` (з теки `джерела`); код виходу 1 при провалі. Друкує таблицю
«рівень: areas.РІВНІ ↔ середнє джерела ± розкид» — частка шаблону й є середнім запису. Перерахунок самих середніх і SD з даних обміру — поза тестом
(дані не в репозиторії): `аудит/перевірка/похибка_вимірів_тіла/вимір.py`.
"""
import os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import areas, похибка_вимірів_тіла as П  # noqa: E402

збої = []


def перевірити(назва, умова):
    """Записує провал з назвою; нічого не кидає, щоб прогін дійшов до кінця."""
    if not умова:
        збої.append(назва)


def main():
    """Усі перевірки й таблиця рівнів; повертає код виходу."""
    js = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "показ", "профілі.js"), encoding="utf-8").read()
    поля_форми = set(re.findall(r"\['мр-[^']+','([^']+)'\]", js.split("const ПОЛЯ_ОБХВАТІВ", 1)[1].split(";", 1)[0]))
    перевірити("обхвати — рівно поля форми", set(П.РЕЄСТР["обхват"]) == поля_форми and поля_форми)
    перевірити("обхвати — усі потрібні", set(areas.ПОТРІБНІ_ОБХВАТИ) <= set(П.РЕЄСТР["обхват"]))
    перевірити("рівні — рівно areas.РІВНІ", set(П.РЕЄСТР["рівень"]) == {н for н, _ in areas.РІВНІ})

    for вид, записи in П.РЕЄСТР.items():
        for назва, з in записи.items():
            в = з["val"]
            перевірити(f"{вид}.{назва}: число чи None", в is None or (isinstance(в, float) and в >= 0))
            перевірити(f"{вид}.{назва}: примітка або місце", з["примітка"] or з["місце"])
            if в:
                перевірити(f"{вид}.{назва}: джерело, місце, спосіб, тір",
                           all(з[к] for к in ("джерело", "місце", "спосіб", "t")))
            if вид == "рівень":
                перевірити(f"{вид}.{назва}: середнє разом із розкидом", (з["середнє"] is None) == (в is None))

    # число стегон — з рисунка джерела, не вписане: Fig. 3, межі −4.08…+3.68 дюйма, ±1.98 SD
    перевірити("стегна: SD з меж згоди Fig. 3", П.похибка("обхват", "стегна") == round(7.76 / 3.96 * 2.54, 2))
    перевірити("талія: місце виміру інше — невідомо", П.похибка("обхват", "талія") is None)
    перевірити("груди, плечі: невідомо", П.похибка("обхват", "груди") is None and П.похибка("обхват", "плечі") is None)

    # Нижня межа рівня «невідомо» — окреме поле запису, не текст примітки: щиколотка лежить над кісточкою (ANSUR II
    # lateralmalleolusheight), підборіддя — над сьомим шийним хребцем (cervicaleheight); в інших рівнів межі нема.
    # Вузол профілю такого рівня стоїть на цій межі (ч27, 14022): числа без джерела в шаблоні нема.
    # Рівень обхвату плечей (середина дельтоподібних м'язів) — над пахвою (axillaheight), під лінією плеча (рішення 13.11).
    МЕЖІ = {"щиколотка": (0.0385, 0.0028, "lateralmalleolusheight"), "підборіддя": (0.8570, 0.0068, "cervicaleheight"),
            "плечі": (0.7607, 0.0092, "axillaheight")}
    for рів, з in П.РЕЄСТР["рівень"].items():
        м = з["нижня_межа"]
        if рів in МЕЖІ:
            середнє, val, стовпець = МЕЖІ[рів]
            перевірити(f"{рів}: нижня межа з джерелом", м and м["середнє"] == середнє and м["val"] == val and
                       all(м[к] for к in ("джерело", "місце", "спосіб")) and стовпець in м["місце"])
            перевірити(f"{рів}: вузол профілю — на нижній межі", dict(areas.РІВНІ)[рів] == м["середнє"])
            перевірити(f"{рів}: середнє і розкид рівня — невідомо", з["середнє"] is None and з["val"] is None)
        else:
            перевірити(f"{рів}: нижньої межі нема", м is None)

    # Орієнтири брифу (ч27, п.7): ім'я точки — ім'я її орієнтира; кожне має код; «середина стегна» — запис реєстру.
    import brief as БР
    імена = [н for н, _ in БР.ОРІЄНТИРИ] + [н for н, _ in БР.ТОЧКИ_ОРІЄНТИРІВ]
    перевірити("орієнтири брифу: ім'я ↔ код", sorted(імена) == sorted(БР.ОРІЄНТИР_КОД))
    перевірити("орієнтири брифу: «литка» — найширша точка, «високе стегно» — високе стегно",
               dict(БР.ОРІЄНТИРИ)["найширшій точці литки"] == "литка" and dict(БР.ОРІЄНТИРИ)["високому стегні"] == "високе_стегно")
    перевірити("орієнтири брифу: «під грудьми» без означення — знято", "під грудьми" not in БР.ОРІЄНТИР_КОД)
    for зріст in (155, 165, 175):
        Н = areas.висоти_рівнів(зріст)
        пах_коліно = (Н["пах"] + Н["коліно"]) / 2
        перевірити(f"{зріст} см: середина стегна — середина паху й коліна (запис `середина_стегна`)",
                   БР.орієнтир(Н, пах_коліно) == "середині стегна" and
                   П.зона_точки_речі("середина_стегна")[0] == ("пах", "коліно"))
        перевірити(f"{зріст} см: найширша точка литки — рівень «литка»", БР.орієнтир(Н, Н["литка"]) == "найширшій точці литки")
        перевірити(f"{зріст} см: високе стегно — 18 см під талією", БР.орієнтир(Н, Н["високе_стегно"]) == "високому стегні")

    # Точка виміру крамниці (рішення 06.11 «п.7: точка речі», п.2): рівень, від якого її відкладають, — рівень шаблону;
    # різниця з ним — з того самого обміру, і з часток сходиться (хребець і acromion — обидва ANSUR II, зріст ≈ 162.8 см);
    # кожна точка таблиць фіду — запис реєстру, копії поруч нема.
    import фід_атрибути as ФА
    рівні = {н for н, _ in areas.РІВНІ}
    for назва, з in П.РЕЄСТР["точка_виміру"].items():
        перевірити(f"точка {назва}: рівень шаблону", з["рівень"] in рівні)
        р = з["різниця_см"]
        перевірити(f"точка {назва}: різниця — число з місцем чи None",
                   р is None or (р["val"] >= 0 and р["місце"] and isinstance(р["середнє"], float)))
        перевірити(f"точка {назва}: без різниці — зсуву нема", (П.зсув_точки_см(назва)[1] is None) == (р is None))
    хр, пл = П.запис("точка_виміру", "шийний_хребець"), П.запис("рівень", "лінія_плеча")
    перевірити("хребець над acromion: різниця сходиться з частками",
               abs((хр["середнє"] - пл["середнє"]) * 162.8 - хр["різниця_см"]["середнє"]) < 0.3)
    таблиці = ([тт for _, т in ФА.ДОВЖИНА_ТОЧКА for тт in (т.values() if isinstance(т, dict) else [т])]
               + list(ФА.ДОВЖИНА_ТОЧКА_СЛОТА.values()))
    перевірити("точки фіду — записи реєстру", all(т in П.РЕЄСТР["точка_виміру"] for тт in таблиці for т in тт))
    перевірити("«по спині» — хребець, ±(6.06 + 1.33) см до плечей",
               ФА.точка_довжини(("шийний_хребець",)) == ("лінія_плеча", 7.39))
    перевірити("низ від верху пояса — «невідомо»", ФА.точка_довжини(("верх_пояса",)) == ("талія", None))
    перевірити("«довжина переду» низу — від пояса", ФА._точки_назви("довжина переду верх", "низ") == ("верх_пояса",))
    _к = {"параметри": {"довжина по спині": "59", "довжина спідниці": "97"}}
    перевірити("комплект: поділ — нижньої частини", ФА.довжина_виробу(_к, "комплект")[:2] == (97.0, "талія"))

    # Точка речі класу чи слова довжини (рішення 06.11 «п.7: точка речі», п.1–3; ч26): клас шкали композитора й слово
    # генеративної сітки ведуть на запис реєстру, а не на рівень; запис — рівні-якорі шаблону й різниця з джерела чи
    # None; без різниці півширина зони «невідомо», а не число; шкала композитора — вигляд записів, копії нема.
    import композитор_річ as КР, силует_запит as СЗ
    for назва, з in П.РЕЄСТР["точка_речі"].items():
        перевірити(f"точка речі {назва}: 1–2 рівні шаблону", 1 <= len(з["рівні"]) <= 2 and set(з["рівні"]) <= рівні)
        перевірити(f"точка речі {назва}: ім'я — не рівень", назва not in рівні)
        перевірити(f"точка речі {назва}: означення з місцем або без обох", bool(з["джерело"]) == bool(з["місце"]))
        р = з["різниця_см"]
        перевірити(f"точка речі {назва}: без різниці — півширини нема", (П.зона_точки_речі(назва)[1] is None) == (р is None))
    перевірити("шкала композитора — записи реєстру", set(П.КЛАС_ТОЧКА.values()) <= set(П.РЕЄСТР["точка_речі"]))
    перевірити("шкала композитора — вигляд записів", КР.РІВЕНЬ_ЗОНА == {
        к: П.зона_точки_речі(т) for к, т in П.КЛАС_ТОЧКА.items()})
    перевірити("слова сітки — записи реєстру", all(т in П.РЕЄСТР["точка_речі"] for _, т in СЗ.ДОВЖИНИ_ВЕРХУ + СЗ.ДОВЖИНИ_НИЗУ))
    перевірити("міді — найвужче місце литки, не рівень «литка» (K-SIL-10)", П.КЛАС_ТОЧКА["литка"] == "найвужче_литки"
               and "литка" not in П.запис("точка_речі", "найвужче_литки")["рівні"]
               and dict(СЗ.ДОВЖИНИ_НИЗУ)["midi"] == П.КЛАС_ТОЧКА["литка"])
    перевірити("міні — середина стегна (тема-10:126), та сама точка у шкалі й сітці",
               dict(СЗ.ДОВЖИНИ_НИЗУ)["mini"] == П.КЛАС_ТОЧКА["міні"] == "середина_стегна")
    H = areas.висоти_рівнів(165)
    перевірити("висота класу й слова — одна точка", КР.висота_рівня("литка", H) == СЗ.висота_довжини("найвужче_литки", H)
               == (round((H["коліно"] + H["щиколотка"]) / 2, 1), None))

    for вид, назва in (("обхват", "стегно"), ("рівень", "pupok"), ("обхвати", "стегна"), ("точка_речі", "литка")):
        try:
            П.похибка(вид, назва)
            перевірити(f"невідоме ім'я {вид}.{назва} — KeyError", False)
        except KeyError:
            pass
    копія = П.запис("рівень", "лінія_плеча")
    копія["val"] = 1.0
    перевірити("запис — копія", П.похибка("рівень", "лінія_плеча") == 0.0087)
    # Лінія плеча й обхват плечей — дві величини з різними іменами (рішення 13.11, п.1): лінія плеча — акроміон, рівень
    # обхвату «плечі» — «невідомо» між акроміоном (верхня межа — ім'я рівня) і пахвою; лінія плеча вузлом профілю не є
    перевірити("лінія плеча — акроміон, обхват плечей — інша точка", "acromialheight" in П.запис("рівень", "лінія_плеча")
               ["місце"] and "дельтоподібн" in П.запис("рівень", "плечі")["примітка"]
               and П.запис("рівень", "плечі")["верхня_межа"] == "лінія_плеча"
               and all(з["верхня_межа"] is None for р, з in П.РЕЄСТР["рівень"].items() if р != "плечі"))
    перевірити("лінія плеча — висота без вузла профілю", "лінія_плеча" in areas.висоти_рівнів(165)
               and "лінія_плеча" not in {nm for nm, _, _ in areas.профіль_тіла(165, dict(плечі=100, груди=92,
                                                                                         талія=74, стегна=100))})

    # Рівень шаблону — середнє запису, копії нема (рішення 06.11 «орієнтири тіла», п.1): частка в `areas.РІВНІ` — те саме
    # число, що в записі; високе стегно — відстанню від природної талії (§2.1), без частки; запис «невідомо» — вузол
    # профілю на нижній межі запису (визнаний орієнтир, вище якого рівень лежить), а не число без джерела (ч27, 14022).
    print("| рівень | areas.РІВНІ | середнє ± розкид | звідки |")
    for рів, частка in areas.РІВНІ:
        з = П.запис("рівень", рів)
        if рів == "високе_стегно":
            перевірити("високе стегно — без частки", частка is None)
            print(f"| {рів} | — | ± похибка рівня талії | {areas.ВИСОКЕ_СТЕГНО_ПІД_ТАЛІЄЮ_СМ:g} см під природною талією, тема-1 §2.1 |")
        elif з["середнє"] is None:
            межа = з["нижня_межа"]
            перевірити(f"{рів}: запис «невідомо» — вузол на нижній межі запису", межа is not None and межа["середнє"] is частка)
            перевірити(f"{рів}: похибка рівня — «невідомо»", з["val"] is None)
            print(f"| {рів} | {частка:.4f} | невідомо | вузол на нижній межі: {межа['місце'].split(';')[0]} |")
        else:
            перевірити(f"{рів}: частка — середнє запису", частка is з["середнє"])
            print(f"| {рів} | {частка:.4f} | {з['середнє']:.4f} ± {з['val']:.4f} | {(з['місце'] or '').split(';')[0]} |")
    перевірити("на нижній межі — рівно підборіддя, плечі й щиколотка", set(areas.рівні_на_нижній_межі()) == {
        р for р, з in П.РЕЄСТР["рівень"].items() if з["середнє"] is None and р != "високе_стегно"} == {
        "підборіддя", "плечі", "щиколотка"})
    перевірити("числа без джерела в areas нема", not hasattr(areas, "_ШАБЛОН_БЕЗ_ДЖЕРЕЛА"))
    H = areas.висоти_рівнів(165)
    перевірити("високе стегно 165 см — 18 см під талією", abs(H["талія"] - H["високе_стегно"] - 18.0) < 1e-9)
    перевірити("порядок рівнів згори вниз на 135–210 см", all(
        all(a > b for a, b in zip([areas.висоти_рівнів(h)[н] for н in areas.ПОРЯДОК_РІВНІВ][:-1],
                                  [areas.висоти_рівнів(h)[н] for н in areas.ПОРЯДОК_РІВНІВ][1:])) for h in range(135, 211)))
    try:
        areas.висоти_рівнів(125)
        перевірити("125 см: високе стегно під стегнами — ValueError", False)
    except ValueError:
        pass

    print("\nвпало: %d%s" % (len(збої), "".join("\n  " + з for з in збої)))
    return 1 if збої else 0


if __name__ == "__main__":
    sys.exit(main())
