# -*- coding: utf-8 -*-
"""Тест записів `похибка_вимірів_тіла`: повнота імен, поля запису, виведення числа з джерела, читання.

Прогін: `python3 тест_похибки_вимірів_тіла.py` (з теки `джерела`); код виходу 1 при провалі. Друкує таблицю
«рівень: areas.РІВНІ ↔ середнє джерела ± розкид». Перерахунок самих середніх і SD з даних обміру — поза тестом
(дані не в репозиторії): `аудит/перевірка/похибка_вимірів_тіла/вимір.py`.
"""
import os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import areas, похибка_вимірів_тіла as П  # noqa: E402

збої = []


def перевірити(назва, умова):
    """Записує провал з назвою; нічого не кидає, щоб прогін дійшов до кінця."""
    if not умова:
        збої.append(назва)


def main():
    """Усі перевірки й таблиця рівнів; повертає код виходу."""
    js = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "показ", "профілі.js"), encoding="utf-8").read()
    поля_форми = set(re.findall(r"\['мр-[^']+','([^']+)'\]", js.split("const ПОЛЯ_ОБХВАТІВ", 1)[1].split(";", 1)[0]))
    перевірити("обхвати — рівно поля форми", set(П.РЕЄСТР["обхват"]) == поля_форми and поля_форми)
    перевірити("обхвати — усі потрібні", set(areas.ПОТРІБНІ_ОБХВАТИ) <= set(П.РЕЄСТР["обхват"]))
    перевірити("рівні — рівно areas.РІВНІ", set(П.РЕЄСТР["рівень"]) == {н for н, _ in areas.РІВНІ})

    for вид, записи in П.РЕЄСТР.items():
        for назва, з in записи.items():
            в = з["val"]
            перевірити(f"{вид}.{назва}: число чи None", в is None or (isinstance(в, float) and в >= 0))
            перевірити(f"{вид}.{назва}: примітка або місце", з["примітка"] or з["місце"])
            if в:
                перевірити(f"{вид}.{назва}: джерело, місце, спосіб, тір",
                           all(з[к] for к in ("джерело", "місце", "спосіб", "t")))
            if вид == "рівень":
                перевірити(f"{вид}.{назва}: середнє разом із розкидом", (з["середнє"] is None) == (в is None))

    # число стегон — з рисунка джерела, не вписане: Fig. 3, межі −4.08…+3.68 дюйма, ±1.98 SD
    перевірити("стегна: SD з меж згоди Fig. 3", П.похибка("обхват", "стегна") == round(7.76 / 3.96 * 2.54, 2))
    перевірити("талія: місце виміру інше — невідомо", П.похибка("обхват", "талія") is None)
    перевірити("груди, плечі: невідомо", П.похибка("обхват", "груди") is None and П.похибка("обхват", "плечі") is None)

    for вид, назва in (("обхват", "стегно"), ("рівень", "pupok"), ("обхвати", "стегна")):
        try:
            П.похибка(вид, назва)
            перевірити(f"невідоме ім'я {вид}.{назва} — KeyError", False)
        except KeyError:
            pass
    копія = П.запис("рівень", "плечі")
    копія["val"] = 1.0
    перевірити("запис — копія", П.похибка("рівень", "плечі") == 0.0087)

    print("| рівень | areas.РІВНІ | середнє ± розкид | шаблон у межах розкиду |")
    понад = set()
    for рів, частка in areas.РІВНІ:
        з = П.запис("рівень", рів)
        if з["val"] is None:
            print(f"| {рів} | {частка:.3f} | невідомо | — |")
            continue
        у_межах = abs(частка - з["середнє"]) <= з["val"]
        if not у_межах:
            понад.add(рів)
        print(f"| {рів} | {частка:.3f} | {з['середнє']:.4f} ± {з['val']:.4f} | {'так' if у_межах else 'НІ'} |")
    # рядки дошки 13855 (талія) і 13856 (коліно) названо в записах; інший набір — записи й дошка розійшлись
    перевірити("понад розкид — талія й коліно", понад == {"талія", "коліно"})

    print("\nвпало: %d%s" % (len(збої), "".join("\n  " + з for з in збої)))
    return 1 if збої else 0


if __name__ == "__main__":
    sys.exit(main())
