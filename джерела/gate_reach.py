def розкладка(корп):
    """Корпус, розкладений на відра гейта — ОДНЕ місце, де ця арифметика живе.

    ЧОМУ ОКРЕМА ФУНКЦІЯ. Розкладку писали всередині `гейт`, і одне відро з пʼяти
    з неї просто випало: «сімʼя не класифікована» (105 із 382) не друкувалось
    ніде, тобто 27 % корпусу зникали між останнім надрукованим рядком і
    відсотком покриття. Дірку не було видно саме тому, що суму ніхто не
    перевіряв: чотири відра друкувались, пʼяте мовчало, і ніщо не звіряло
    їхню суму з `len(корп)`. Тепер розкладка — значення, яке можна порахувати
    без 30-хвилинного прогону батареї, і `прилади/розділи_гейтів.py` це робить.
    """
    import rule_genus as РР
    род = РР.знаменник(корп)
    мусять = {i for i in род["так"] if РР.слід(i) == "знахідка"}
    return dict(мусять=мусять, інфра=род["так"] - мусять,
                заблоковані=род["заблоковані"], ні=род["ні"], невідомі=род["невідомі"])


def рядки_розкладки(корп, р=None):
    """Рядки звіту про розкладку корпусу + гучний рядок, коли сума не сходиться.

    Рядок про некласифіковані сімʼї сформульовано як «НЕ в жодному відрі вище», а
    не як новий провал: покриття від цього не гіршає, воно просто перестає
    ховати знаменник, з якого його рахують.
    """
    import rule_genus as РР
    р = р or розкладка(корп)
    заблок = р["заблоковані"]
    рядки = ["  У КОРПУСІ ВСЬОГО:           %4d" % len(корп),
             "    з них МУСЯТЬ бути кодом і називати себе:  %4d  ← знаменник"
             % len(р["мусять"]),
             "    інфраструктура (кодом так, сліду не винні): %4d" % len(р["інфра"]),
             "    заблоковані відсутнім входом:             %4d"
             % sum(len(v) for v in заблок.values())]
    for б, м in sorted(заблок.items(), key=lambda x: -len(x[1])):
        рядки.append("        %-30s %3d" % (б, len(м)))
    рядки.append("    у цьому шарі кодом бути не мають:         %4d" % len(р["ні"]))
    рядки += РР.рядки_невідомих(р["невідомі"], відступ="    ",
                                підпис="сімʼя не класифікована (НЕ в жодному відрі вище)",
                                ширина=50)
    # САМОПЕРЕВІРКА СУМИ. Дірка вже жила тут місяцями й була невидима саме тому,
    # що ніхто не звіряв суму відер із корпусом. Вдруге вона мовчки не зʼявиться.
    сума = (len(р["мусять"]) + len(р["інфра"]) + sum(len(v) for v in заблок.values())
            + len(р["ні"]) + len(р["невідомі"]))
    if сума != len(корп):
        рядки.append("    ⛔ розкладка не сходиться: відра дають %d, у корпусі %d"
                     % (сума, len(корп)))
    return рядки


def розбіжність_шару(шар, у_коді):
    """Оголошений `шар` правила НЕ перетинається з файлами, де воно стоїть у коді.

    ЧОМУ ЦЕ ТУТ, А НЕ В ТРЬОХ ЗВІТАХ ОКРЕМО (наряд Н-V21-045). Докстрінг
    `rule_genus` обіцяє: «`шар` — це намір, а не вимір… розбіжність між цими
    двома колонками — дефект, який гейт зобовʼязаний показати, а не згладити».
    Показувати її не було кому: обидві колонки стояли поруч у `ЗВЕДЕННЯ.md` і
    порівнювало їх лише око, тобто ніхто. Предикат лежить у гейті, бо його
    читають троє — `зведення`, `правила` і сам гейт, — і три копії розійшлись
    би на першому ж записі з комою.

    ПОРОЖНЄ — НЕ РОЗБІЖНІСТЬ. Ані «шару не оголошено» («—»), ані «у коді нема»
    розбіжністю не є: перше — відсутність наміру, друге вже має власний
    вердикт («нема в коді»). Дефект саме тут — коли сказано і те, й те, і вони
    вказують у різні боки.
    """
    оголошено = {x.strip() for x in (шар or "—").split(",")
                 if x.strip() and x.strip() != "—"}
    факт = {os.path.basename(ф) for ф in (у_коді or [])}
    return bool(оголошено) and bool(факт) and not (оголошено & факт)


