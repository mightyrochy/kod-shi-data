def рядки_правил(шлях="."):
    """{ID: {(файл, номер_рядка)}} — лише ВИКОНУВАНІ рядки, без коментарів."""
    out = {}
    for f in os.listdir(шлях):
        if not f.endswith(".py") or _прилад(f):
            continue
        повний = os.path.abspath(os.path.join(шлях, f))
        for i, рядок in enumerate(open(повний, encoding="utf-8").read().splitlines(), 1):
            гол = рядок.split("#")[0]
            for r in ID.findall(гол):
                out.setdefault(r, set()).add((повний, i))
    return out


def виконані_рядки():
    """Які рядки справді виконались. sys.settrace дорогий, тож батарея тут
    коротка — цього досить, щоб відрізнити «не викликається взагалі» від
    «викликається, але ID губиться перед виходом»."""
    import bridge
    бачені = set()

