def _рядки_другого_проходження(корп, знахідки, спільні, чекліст, у_сліді, мертві):
    """Реєстр `ДРУГЕ_ПРОХОДЖЕННЯ` проти ПРОГОНУ: що збіглось, що ні.

    ЧОМУ ЦЕ ДРУКУЄТЬСЯ, А НЕ ЛЕЖИТЬ ПОРУЧ. Двічі в цьому файлі вже стояв список,
    який ніщо не звіряло з кодом, і двічі він розійшовся мовчки: `ЦІЛІ_ОБРАЗІВ`
    зсунулись на елемент і сім рядків звіту стали на чужому доказі, а розкладка
    корпусу не сходилась із корпусом місяцями. Тому реєстр звіряється з тим
    самим прогоном, який дав числа вище, і розбіжність друкується ПОІМЕННО.

    ЩО САМЕ ЗВІРЯЄТЬСЯ — рівно те, що реєстр стверджує, і нічого понад:
      «а» і «б» → правило мусить ДОХОДИТИ до виходу в цьому прогоні (знахідкою,
                  полем `також_правила` або, для правил-процесів, слідом);
      «в»       → правило мусить бути НАЗВАНЕ як чесно вимкнене — пунктом
                  чекліста, записом `БЕЗ_ВХОДУ` або сусідньою знахідкою; його
                  мовчання лишається законним, безіменність — ні.
    Правило, яке реєстр числить розібраним, а прогін не дістає, стоїть у
    «⛔ РЕЄСТР РОЗІЙШОВСЯ З ПРОГОНОМ» — і це провал реєстру, не правила.
    """
    рядки, розбіжні, звірено = [], [], 0
    досяжні = set(знахідки) | set(спільні) | set(у_сліді)
    названі = досяжні | set(чекліст)
    поза = sorted(set(ДРУГЕ_ПРОХОДЖЕННЯ) - set(корп))
    за_літерою = {"а": [], "б": [], "в": []}
    for ід, (літ, доказ, чому) in sorted(ДРУГЕ_ПРОХОДЖЕННЯ.items()):
        за_літерою.setdefault(літ, []).append(ід)
        if ід in ПОЗА_БАТАРЕЄЮ:
            continue          # названий виняток, друкується окремо нижче
        звірено += 1
        ок = (ід in названі) if літ == "в" else (ід in досяжні)
        if not ок:
            розбіжні.append((ід, літ, доказ, чому))
    рядки.append("  ── ДРУГЕ ПРОХОДЖЕННЯ: (а)/(б)/(в) по кожному з %d ──"
                 % len(ДРУГЕ_ПРОХОДЖЕННЯ))
    рядки.append("  (а) батарея не мала умови правила:            %3d"
                 % len(за_літерою["а"]))
    рядки.append("  (б) правило діяло, ID у виході не стояв:      %3d"
                 % len(за_літерою["б"]))
    рядки.append("  (в) чесно вимкнене, поле названо:             %3d"
                 % len(за_літерою["в"]))
    if поза:
        рядки.append("  ⛔ ID реєстру, яких нема в корпусі (%d): %s"
                     % (len(поза), ", ".join(поза)))
    for ід, чому in sorted(ПОЗА_БАТАРЕЄЮ.items()):
        рядки.append("  ~ %-12s ПОЗА ЦІЄЮ БАТАРЕЄЮ: %s" % (ід, чому[:64]))
    if розбіжні:
        рядки.append("  ⛔ РЕЄСТР РОЗІЙШОВСЯ З ПРОГОНОМ (%d) — провал реєстру, не правил:"
                     % len(розбіжні))
        for ід, літ, доказ, чому in розбіжні:
            рядки.append("     (%s) %-12s проба %-22s %s" % (літ, ід, доказ, чому[:58]))
    else:
        # Число тут — ЗВІРЕНІ, а не всі: два записи `ПОЗА_БАТАРЕЄЮ` не звіряються
        # цим прогоном за побудовою, і писати їх у «✓» означало б зарахувати собі
        # перевірку, якої не було.
        рядки.append("  ✓ звірено %d із %d: кожен доходить до виходу або названий "
                     "вимкненим (решта — `ПОЗА_БАТАРЕЄЮ` вище)"
                     % (звірено, len(ДРУГЕ_ПРОХОДЖЕННЯ)))
    # Правило, яке прогін числить мертвим, а реєстр про нього мовчить: другий бік
    # тієї самої звірки. Без нього реєстр «повний» рівно доти, доки ніхто не
    # додав правила.
    без_рішення = sorted(set(мертві) - set(ДРУГЕ_ПРОХОДЖЕННЯ))
    if без_рішення:
        рядки.append("  ⚠ мертві БЕЗ рішення в реєстрі (%d): %s"
                     % (len(без_рішення), ", ".join(без_рішення[:14])))
    return рядки


def клас_сліду(ід):
    """Що правило винне виходу: «знахідка» | «слід» | «інфра».

    «знахідка» — мусить назвати себе у виході рядком, який людина або модель
                 може взяти й щось із ним зробити;
    «слід»     — правило-процес: іменований запис у точці спрацювання і є його
                 законним виходом (рішення вище, поіменно);
    «інфра»    — іменованого сліду не винне взагалі (`rule_genus.слід`).
    """
    import rule_genus as РР
    к = РР.слід(ід)
    if к != "знахідка":
        return к
    return "слід" if ід in СЛІД_ЗАКОННИЙ else "знахідка"


# ── ДВА КАНАЛИ ВИХОДУ, ЯКИХ ГЕЙТ НЕ ЧИТАВ ЗОВСІМ (друге проходження) ─────────
# ЩО ЦЕ МІНЯЄ В РІШЕННІ (правило 3, before/after, 17.09.2026). Гейт брав із
# знахідки РІВНО поле `правило` і більше нічого. Два канали через це були для
# нього невидимі, і правила, чий єдиний вихід — один із них, звітувались
# мертвими при повністю живому емітенті. Обидва — не обхідні шляхи, а рішення
# корпусу, ухвалені письмово:
#
# 1. `також_правила` — СПІЛЬНИЙ МЕХАНІЗМ, ОДИН РЯДОК. Корпус кілька разів
#    прямо каже, що два ID — це одне твердження на двох рівнях таксономії, і
#    забороняє другу знахідку з того самого виміру: K-SIL-04/07 («is the same
#    mechanism») їдуть на знахідці K-COL-01, K-KOH-04 — на K-REG-01, K-COMP-06 —
#    на ремонті K-INT-04, K-KOH-03 — на розкиді формальності. Поле стоїть у
#    контракті виходу (`протокол.py`: `"також_правила": список(РЯДОК)`) і доїжджає
#    до вердикту (`pipeline.py:1019`), тобто ID СТОЇТЬ У РЯДКУ, ЯКИЙ БАЧИТЬ
#    ЛЮДИНА. Не читати його означало карати правила за те, що система відмовилась
#    вимовляти той самий вимір двічі, — рівно та хвороба, від якої сімʼя силуету
#    вже відмовилась (K-SIL-01 злито з K-SIL-03).
#    ЧОМУ ОКРЕМИМ ЧИСЛОМ, А НЕ ТИХО В ЗАГАЛЬНОМУ. «Правило назвало себе на чужій
#    знахідці» — слабше твердження за «правило видало власний рядок»: суті в
#    нього своєї нема. Тому воно рахується, друкується окремим рядком і поіменно.
#
# 2. ЧЕКЛІСТ — ТРИСТАНОВИЙ, І «БЕЗ ВХОДУ» ТУТ НЕ МОВЧАННЯ. Чотири чеклісти
#    `суд_образу` (надлишок, прісність, палітра, аксесуари) ведуть кожен пункт зі
#    станом «провал / пройдено / без входу», з переліком своїх правил і з назвою
#    того, чого бракує. Це і є та форма, у якій корпус просить казати «правило
#    перевірено й не має входу» замість тиші (K-IO-04). Формою знахідки пункт не
#    є й бути не має: вироку над річчю в ньому нема, `суть` — нема, і
#    `знахідка.це_знахідка` його законно не бачить. Але ID у виході він НЕСЕ, і
#    правило, яке чесно вимкнене з названим полем, — це третій стан, а не мертве.
def знахідки_дерева(вихід):
    """(власні, спільні) — ID, названі у знахідках дерева.

    `власні` — поле `правило`: правило видало ВЛАСНИЙ рядок.
    `спільні` — поле `також_правила`: правило назвало себе на знахідці спільного
                механізму. Множини не перетинаються за побудовою: ID, що стоїть
                хоч раз власним, у `спільні` не повертається.
    """
    import знахідка as ЗН
    власні, спільні = set(), set()
    for _ш, з in ЗН.усі(вихід):
        if з.get("правило"):
            власні.add(з["правило"])
        for r in (з.get("також_правила") or ()):
            if r:
                спільні.add(str(r))
    return власні, спільні - власні


def чеклістні_дерева(вихід, корінь=""):
    """{ID: {стан, …}} — правила, названі пунктами тристанових чеклістів.

    Пункт розпізнається за ФОРМОЮ, а не за місцем, — з тієї самої причини, по
    якій так зроблено в `знахідка.усі`: перелік відер тут щоразу відставав би від
    коду. Форма пункта — `правила` плюс `стан`; форма рядка вердикту
    (`чекліст_вердикту`) — `правила` плюс `вимкнено`/`провал`.
    """
    out = {}

    def _додати(правила, стан):
        for r in (правила or ()):
            if r:
                out.setdefault(str(r), set()).add(стан)

    def обхід(в):
        if isinstance(в, dict):
            # пункт `суд_образу.чеклісти`
            if "правила" in в and "стан" in в:
                _додати(в.get("правила"), str(в.get("стан")))
                return
            # бік `pipeline.чекліст_вердикту`
            if "правила" in в and ("вимкнено" in в or "провал" in в or "без_входу" in в):
                for п in (в.get("вимкнено") or []):
                    if isinstance(п, dict):
                        _додати(п.get("правила"), "без входу")
                _додати(в.get("правила"), "у чеклісті")
                return
            for v in в.values():
                обхід(v)
        elif isinstance(в, (list, tuple)):
            for v in в:
                обхід(v)

    обхід(вихід)
    return out


