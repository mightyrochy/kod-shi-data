def _навмисні_образи(F, тіло, H):
    """Кожен образ — під названу гілку. Виняток гаситься навмисно: мета батареї —
    ДІСТАТИ гілки, а не впасти на першій, у якої бракує поля."""
    import pipeline
    # ЗНАЙДЕНО ПЕРШИМ ЖЕ ПРОГОНОМ ЦІЄЇ БАТАРЕЇ: `вето_покриття` — це dict
    # {"зони": [...], "ноги_вище_см": N}, а не список. Список валив увесь виклик
    # AttributeError'ом на `вето.get`, і всі сім образів мовчки не доїжджали.
    # Мовчки — бо батарея гасить винятки, щоб дістати гілки, а не падати. Ціна
    # цього рішення названа тут: зламаний вхід виглядає рівно як мертве правило.
    сцен = [dict(нагода="робота", дрес_код="business", темп_c=8.0,
                 вето_покриття=dict(зони=["декольте"])),
            dict(нагода="свято", темп_c=22.0),
            dict(нагода="робота", темп_c=8.0, source="protocolized"),
            # 24.08.2026: сцен зі ставками — без нього K-KOH-07 (асиметрія ризику)
            # не мав входу в жодному прогоні батареї
            dict(нагода="вечеря", господар=True, темп_c=18.0)]
    # ДВА ТІЛА В БАТАРЕЇ — НЕ НЕДБАЛІСТЬ. Базова трійка (прогін_зібраного) іде на
    # тілі БЕЗ виміряного паху: там живе K-BOD-05-«питання» (правило-утримання).
    # Навмисні образи йдуть на тілі З пахом: там живе K-FIT-04 (вісь виміряна,
    # посадка пояса стає важелем). Одне тіло на всю батарею гасило б одне з двох —
    # обидва стани входу реальні, і система мусить жити в обох.
    import fit as _ПС
    тіло = _ПС.тіло(168, dict(плечі=98, груди=92, талія=72, стегна=100,
                              коліно=35.0, литка=36.0, щиколотка=22.0),
                    рівні_см={"пах": 75.6})
    for _чому, речі in НАВМИСНІ(H):
        for с in сцен:
            try:
                pipeline.перевірити_образ(F, [dict(r) for r in речі], тіло=тіло, **с)
            except Exception:
                pass


