                                  # ЛІЧБА ЗБОЇВ ВИХОДИТЬ ІЗ ФУНКЦІЇ, а не лише в
                                  # текст: без неї код виходу нижче не має з чого
                                  # рахуватись, і «⛔ ЧИСЛА НИЖЧЕ НЕПОВНІ» лишалось
                                  # рядком для ока над мовчазним нулем.
                                  збої=len(збої),
