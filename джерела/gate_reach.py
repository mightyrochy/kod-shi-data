def план_батареї():
    """[(підпис, риси, нагода)] — що з чим ганяє `прогін`. ОДНЕ місце, де ця
    арифметика живе: доти вона стояла двома вкладеними циклами в `прогін`, і
    будь-який новий профіль або нагода множились на все інше.

    ТРИ ЧАСТИНИ, І КОЖНА З ВЛАСНОЮ ПРИЧИНОЮ:
      · чотири базові профілі × чотири базові нагоди — рівно те, що було, щоб
        числа лишались звірюваними з попередніми прогонами;
      · два нові профілі (низький зріст, сивина) × ОДНА нагода — вони додані
        заради ВХОДУ двох правил, а не заради матриці; ганяти їх по всіх нагодах
        означало б платити за те, чого ніхто не міряє;
      · сім погодних і вечірніх сцен × ОДИН профіль — обґрунтування вище.
    """
    план = [(п, р, н) for п, р in БАТАРЕЯ[:4] for н in НАГОДИ]
    план += [(п, р, НАГОДИ[0]) for п, р in БАТАРЕЯ[4:]]
    п0, р0 = БАТАРЕЯ[0]
    план += [(п0 + " · сцена", р0, н) for н in СЦЕНИ_ПОГОДИ]
    return план


