    # ── ДВА КАНАЛИ, ЯКІ ГЕЙТ ДОТИ НЕ ЧИТАВ (друге проходження) ────────────
    # Обидва друкуються ОКРЕМИМИ рядками й поіменно, а не тихо в загальному
    # числі: «правило назвало себе на чужій знахідці» і «правило чесно вимкнене
    # з названим полем» — слабші твердження за «правило видало власний рядок», і
    # злити їх у покриття означало б зробити з них алібі. Обґрунтування кожного —
    # при `знахідки_дерева` / `чеклістні_дерева`.
    _спільні = sorted(спільні & мусять)
    рядки.append("  назвало себе на ЧУЖІЙ знахідці (`також_правила`): %4d"
                 % len(_спільні))
    for _r in _спільні:
        рядки.append("       %-12s спільний механізм: власної суті в нього нема" % _r)
    # Чекліст: лічимо лише ті, у кого ІНШОГО виходу нема. У кого є знахідка або
    # законний слід, пункт чекліста нічого не додає, і рахувати його вдруге
    # означало б те саме подвійне зарахування, проти якого написаний П-17.
    _чек_сам = sorted(r for r in (set(чекліст) & мусять)
                      if r not in знахідки and r not in спільні and r not in у_сліді)
    рядки.append("  ЧЕСНО ВИМКНЕНЕ: єдиний вихід — пункт чекліста:    %4d"
                 % len(_чек_сам))
    for _r in _чек_сам:
        рядки.append("       %-12s стан(и): %s" % (_r, ", ".join(sorted(чекліст[_r]))))
    рядки.append("  згадується будь-де у виході:         %4d" % len(у_виході & мусять))
    рядки.append("  у виконуваному коді:                 %4d"
                 % len((set(код) - {r for r, ф in код.items()
                                    if all(v == 'коментар' for v in ф.values())}) & мусять))
    # ── ОГОЛОШЕНИЙ ШАР ПРОТИ ФАКТИЧНОГО (наряд Н-V21-045) ─────────────────
    # Саме цьому гейту докстрінг `rule_genus` обіцяв показувати розбіжність
    # наміру й місця. Рядок друкується завжди, і нуль тут — теж вимір.
    _розб = sorted(r for r in корп
                   if розбіжність_шару(РР.рід(r).get("шар"),
                                       [ф for ф, як in (код.get(r) or {}).items()
                                        if як == "код"]))
    рядки.append("  шар≠код (оголошено одне, у коді інше): %4d" % len(_розб))
    for r in _розб[:12]:
        рядки.append("     %-12s оголошено %-34s у коді %s"
                     % (r, (РР.рід(r).get("шар") or "—")[:34],
                        ", ".join(sorted(ф for ф, як in (код.get(r) or {}).items()
                                         if як == "код"))[:34]))
    if len(_розб) > 12:
        рядки.append("     … і ще %d (повний перелік — `зведення.py`)" % (len(_розб) - 12))
    _поза = РР.поза_корпусом(корп)
    if _поза:
        рядки.append("")
        рядки.append("  ⚠ КОД ЦИТУЄ ПРАВИЛА, ЯКИХ НЕМА В ЖОДНОМУ .md (%d):" % len(_поза))
        for r, чому in sorted(_поза.items()):
            рядки.append("     %-12s %s" % (r, str(чому)[:96]))
    рядки.append("")
    рядки.append("  ── ГІЛКА ОЖИЛА? кожен навмисний образ ізольовано проти своєї цілі ──")
    рядки.append("  (у сукупному сліді ID може бути, а власний образ цілі — мовчати:")
    рядки.append("   це різні твердження, і лише друге доводить, що гілка жива)")
    for _ц, _ж, _ч in гілки_образів:
        _мітка = ("БЕЗ ЦІЛІ" if _ж is None else ("ЖИВА  " if _ж else "МЕРТВА"))
        рядки.append("   %-8s %-10s %s" % (_мітка, _ц, _ч[:58]))
    рядки.append("")
    рядки.append("  ── стара шкала, для звірки з попередніми прогонами ──")
    рядки.append("  у корпусі:                  %4d" % len(корп))
    рядки.append("  згадано в коді:             %4d  (%.0f%% корпусу)"
                 % (len(код), 100 * len(код) / max(1, len(корп))))
    рядки.append("  з них ЛИШЕ в коментарях:    %4d  ← presence-аудит рахує їх як «є»"
                 % len(лише_коментар))
    рядки.append("  у виконуваному коді:        %4d" % len(у_коді_справді))
    рядки.append("  доходить до ПАКЕТА коду:    %4d  (%.0f%% від згаданих у коді)"
                 % (len(у_пак & set(код)), 100 * len(у_пак & set(код)) / max(1, len(код))))
    рядки.append("  доходить до ВИХОДУ моста:   %4d  (%.0f%%)  ← це бачить тестувальник"
                 % (len(у_виході & set(код)),
                    100 * len(у_виході & set(код)) / max(1, len(код))))
    втрачені = sorted((у_пак & set(код)) - у_виході)
    рядки.append("  ЗГУБЛЕНО НА МЕЖІ МОСТА:     %4d" % len(втрачені))
    рядки.append("  (з ярусу «пакет» вирізано %d ID, що жили ЛИШЕ у статичному"
                 % len(лише_статичні - у_пак))
    рядки.append("   списку `обмеження` — він однаковий для будь-якого профілю)")
    рядки.append("")
    # ── РОЗДІЛИТИ ДВІ РІЗНІ БІДИ ──────────────────────────────────────
    # «Нема сліду у виході» змішує два випадки, і лікуються вони по-різному:
    #   (а) рядок із правилом НЕ ВИКОНУВАВСЯ — правило мертве;
    #   (б) рядок виконувався, але ID не дожив до JSON — правило працює,
    #       а лог не може нічого приписати. Це дефект простежуваності, і
    #       саме через нього presence-аудит виглядав правдивим.
    # ТРЕТІЙ СТАН ВИХОДИТЬ ІЗ ЦЬОГО ПОДІЛУ ЗОВСІМ (друге проходження). Правило,
    # чий ID стоїть у виході полем `також_правила` або пунктом чекліста, СЕБЕ
    # НАЗВАЛО — воно не мертве й не непростежуване, і тримати його в (а)
    # означало б звітувати мертвим рівно те, що корпус вирішив вимовляти
    # спільним рядком або тристановим пунктом. Обидві множини вже надруковані
    # вище власними рядками, поіменно; тут вони віднімаються.
    рядки_ID = рядки_правил(корінь)
    # ТОЙ САМИЙ `корінь`, А НЕ ДВА РІЗНІ: `виконані_рядки` рахувала свою карту
    # рядків сама, від теки ЦЬОГО файлу, — і на виклику з іншим коренем дві
    # карти вказували б у різні дерева мовчки.
    виконані = виконані_рядки(рядки_ID)
    мертві, безіменні = [], []
    for r in sorted(у_коді_справді - у_виході - у_сліді - спільні - set(чекліст)):
        точки = рядки_ID.get(r, set())
        if r in у_пак:
            continue                      # це не мертве — це згублене мостом
        (безіменні if (точки & виконані) else мертві).append(r)
    мертві_мусять = [r for r in мертві if r in мусять]
    мертві_решта = [r for r in мертві if r not in мусять]
    рядки.append("  (а) РЯДОК ІЗ ПРАВИЛОМ НЕ ВИКОНАВСЯ — правило мертве (%d, з них %d МУСЯТЬ):"
                 % (len(мертві), len(мертві_мусять)))
    for r in мертві_мусять:
        рядки.append("     %-12s %s" % (r, ", ".join(sorted(код[r]))))
    if мертві_решта:
        рядки.append("     ── решта (інфраструктура / заблоковані / не цей шар):")
        for r in мертві_решта:
            рядки.append("     %-12s [%s] %s" % (r, РР.рід(r)["виконуваний"],
                                                 ", ".join(sorted(код[r]))))
    рядки.append("")
    рядки.append("  (б) ВИКОНАВСЯ, АЛЕ ID НЕ ДІЙШОВ ДО ВИХОДУ — не простежується (%d):"
                 % len(безіменні))
    for r in безіменні:
        рядки.append("     %-12s %s" % (r, ", ".join(sorted(код[r]))))
    рядки.append("")
    рядки.append("  (в) СПРАЦЮВАЛО Й ЛЯГЛО В ПАКЕТ, АЛЕ МІСТ НЕ ВІДДАЄ (%d):" % len(втрачені))
    for r in втрачені:
        рядки.append("     %-12s %s" % (r, ", ".join(sorted(код.get(r, {})))))
    # ── РЕЄСТР ДРУГОГО ПРОХОДЖЕННЯ ЗВІРЯЄТЬСЯ ТУТ, А НЕ ВИЩЕ ─────────────────
    # `мертві` рахуються рівно в цьому місці, і звірка «мертве БЕЗ рішення в
    # реєстрі» без них не має чого питати. Ставити виклик раніше й передавати
    # порожній список означало б написати перевірку, яка мовчить завжди, — той
    # самий `_перевірка_гілок`, що був написаний і не викликався нізвідки.
    рядки.append("")
    рядки += _рядки_другого_проходження(корп, знахідки, спільні, чекліст, у_сліді,
                                        мертві_мусять)
    німі = мертві + безіменні
    if лише_коментар:
        рядки.append("")
        рядки.append("  ЛИШЕ В КОМЕНТАРЯХ (%d):" % len(лише_коментар))
        for r in sorted(лише_коментар):
            рядки.append("     %-12s %s" % (r, ", ".join(sorted(код[r]))))
    return "\n".join(рядки), dict(корпус=len(корп), мусять=len(мусять),
                                  у_сліді=len(у_сліді & мусять), у_коді=len(код),
                                  знахідки=len(знахідки & мусять),
                                  спільні=len(_спільні), чекліст=len(_чек_сам),
                                  лише_слід=len(_лише_слід),
                                  лише_коментар=len(лише_коментар),
                                  у_виході=len(у_виході & set(код)),
                                  у_пакеті=len(у_пак & set(код)),
                                  # ЛІЧБА ЗБОЇВ ВИХОДИТЬ ІЗ ФУНКЦІЇ, а не лише в
                                  # текст: без неї код виходу нижче не має з чого
                                  # рахуватись, і «⛔ ЧИСЛА НИЖЧЕ НЕПОВНІ» лишалось
                                  # рядком для ока над мовчазним нулем.
                                  збої=len(збої),
                                  мертві=мертві, безіменні=безіменні, втрачені=втрачені)


