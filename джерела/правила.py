# -*- coding: utf-8 -*-
"""ДОВІДНИК ПО КОЖНОМУ ПРАВИЛУ: що каже корпус, де це в коді, що з ним робила сесія.

ЧОМУ ЦЕ ПРИЛАД, А НЕ ДОКУМЕНТ. Та сама причина, що і в `зведення.py`: 382 рядки,
набрані руками, застаріють на першій правці й не будуть перевірними. Тут кожна
колонка — вимір або витяг із git, і кожен прогін дає поточний стан.

ЧИМ ЦЕ ВІДРІЗНЯЄТЬСЯ ВІД `зведення.py`. Те зведення відповідає на питання «чи
правило ДІЄ» (слід у виході, вердикт). Це — на питання «ЩО воно каже і ЩО з ним
робили»: формулювання з корпусу, шар, файли з виконуваним рядком, і — головне —
перелік правок сесії, витягнутий із git, а не з пам'яті.

КОЛОНКИ І ЗВІДКИ ВОНИ:
  правило      — ID (`корпус.ід`)
  теми         — файли тем, де ID названий
  формулювання — блок корпусу біля ID, стиснутий (той самий добір, що в `звірка.py`:
                 блок із FORCE важить більше за згадку)
  рід / шар    — `rule_genus.рід` і оголошене місце
  у коді       — файли, де ID стоїть у ВИКОНУВАНОМУ рядку (`gate_reach.з_коду`)
  правки сесії — коміти, у ШМАТКУ дифу яких (з контекстом ±25 рядків) стоїть
                 цей ID. Читається «зміна в блоці правила», не «зміна правила».
                 Мітка каже, ДЕ саме, і це не педантизм: перша версія рахувала
                 будь-який доданий рядок за «код» і дала 392 з 392 — число, що
                 виглядає як вимір і ним не є; друга шукала ID у самому
                 зміненому рядку й знайшла 3 правки із 7 перевірених руками.
                 Розділено:
                   «код»       — виконуваний рядок у .py/.js/.html
                   «коментар»  — рядок-коментар у тих самих файлах
                   «документ»  — рядок у .md (запис аудиту)
                   «запис»     — ID названий у поясненні коміта

ЧОГО ЦЕЙ ФАЙЛ НЕ КАЖЕ: чи правило ПРАВЕ, і чи сказане ним придатне до вжитку.
Перше не міряється кодом узагалі; друге — лише читанням того, що дістає споживач
(див. `аудит/A10_ЩО_ДОЇЖДЖАЄ.md`).

Прогін:  python3 правила.py [--md ФАЙЛ] [--база КОМІТ]
"""
import sys, os, re, json, subprocess, collections

_ТУТ = os.path.dirname(os.path.abspath(__file__)) or "."
sys.path.insert(0, _ТУТ)
import корпус as КР
import rule_genus as РР
import gate_reach as ГД

# Коміт розпакування джерел: усе після нього — робота сесії аудиту.
БАЗА_ЗА_ЗАМОВЧУВАННЯМ = "8b20ab7"
# `P-` і `E-` теж ловимо: код цитує P-PRT-01/02, яких у темах нема, і мовчазне
# ігнорування таких ID — рівно та сліпота, від якої лікується решта приладів.
ID = re.compile(r'\b([KRPE]-[A-ZА-Я0-9]{2,5}-\d{2}[a-zа-я]?)\b')


def _git(*a, репо=None):
    # `core.quotepath=false` — не косметика. Без нього git екранує кириличні
    # шляхи в octal (`"b/\320\264..."`), рядок `+++ b/` не збігається, розбір
    # дифу не знає файла, і КОЖНА згадка ID падає в кошик «документ». Перша
    # версія цього приладу дала через це 0 правок коду з 392 — число, що
    # виглядає як вимір і ним не є. Другий раз поспіль на тому самому місці.
    return subprocess.run(("git", "-c", "core.quotepath=false") + a,
                          cwd=репо or os.path.dirname(_ТУТ),
                          capture_output=True, text=True).stdout


def формулювання(максимум=420):
    """{ID: (тема, стислий блок корпусу)}.

    ДОБІР БЛОКУ — НЕ «ПЕРША ЗГАДКА». Правило згадується в кількох темах, і
    згадка не дорівнює означенню. Виміряно на K-COMP-01: у темі-10 стоїть
    «**K-COMP-01**, not from this source…» (посилання в чужому доказі), у темі-4 —
    «**K-COMP-01. Target the middle of the coordination range…** WHEN: … FORCE: …»
    (означення). Перша версія добору давала обом однаковий бал, і `max` брав
    той, що трапився раніше за абеткою файлів, — тобто ЗГАДКУ.
    Тепер вирішальна ознака — ФОРМА означення: «ID.» з великої літери далі,
    плюс структурні маркери корпусу (WHEN / FORCE / BREAKS / CHANGES).
    """
    тексти = КР.текст()
    out = {}
    for імя, t in sorted(тексти.items()):
        for ід in set(КР.ID_ПРАВИЛА.findall(t)):
            for m in re.finditer(r'(?:^|\n)[>\s#*]*\*{0,2}' + re.escape(ід) + r'[.\s—–,*]', t):
                кін = min([x for x in (t.find('\n\n> **', m.end()),
                                       t.find('\n### ', m.end()), m.end() + 2000) if x > 0])
                бл = ' '.join(t[m.start():кін].split())
                хвіст = t[m.end() - 1:m.end() + 3]
                бал = 0
                # ФОРМА ОЗНАЧЕННЯ: «K-XXX-NN. Слово…» — крапка одразу після ID
                if re.match(r'^\.\s*\*{0,2}\s*[A-ZА-ЯІЇЄ]', хвіст):
                    бал += 5
                бал += 3 if re.search(r'\bFORCE\b\s*[:*]', бл) else 0
                бал += 2 if re.search(r'\bWHEN\b\s*[:*]', бл) else 0
                бал += 2 if re.search(r'\*\*' + re.escape(ід), t[max(0, m.start() - 4):m.end()]) else 0
                бал += 1 if re.search(r'\b(BREAKS|CHANGES)\b', бл) else 0
                # довжина — лише як розвʼязання нічиєї, і в останню чергу
                ключ = (бал, len(бл))
                поточний = out.get(ід)
                if поточний is None or ключ > поточний[0]:
                    out[ід] = (ключ, імя, бл[:максимум])
    return {k: (v[1], v[2]) for k, v in out.items()}


_КОД = (".py", ".js", ".html")
_КОМЕНТАР = re.compile(r'^\s*(#|//|\*|/\*|"""|\'\'\')')
_КОНТЕКСТ = 25   # рядків навколо зміни, у яких шукається ID правила


def правки(база=БАЗА_ЗА_ЗАМОВЧУВАННЯМ, контекст=_КОНТЕКСТ):
    """{ID: [{коміт, дата, тема, у_коді, у_коментарі, у_документі, у_записі}]}.

    ЯК ПРИПИСУЄТЬСЯ ПРАВКА, І ЧОГО ЦЕ НЕ ЗНАЧИТЬ. Правка приписується правилу,
    якщо його ID стоїть у ТОМУ САМОМУ ШМАТКУ дифу (`hunk`), узятому з широким
    контекстом. Це «зміна в блоці цього правила», а НЕ «зміна цього правила»:
    один шматок може накрити двох сусідів.

    ЧОМУ НЕ ВУЖЧЕ. Перша версія шукала ID у самому зміненому рядку — і з семи
    правок, які я перевірив руками, знайшла три. Причина проста: суть правила
    живе рядком нижче за виклик `_зн("K-SIL-06", …)`, і при зміні тексту ID у
    доданому рядку не зʼявляється. Вужчий критерій давав тихий недолік — гірший
    за широкий, бо виглядав як повнота.

    ЧОМУ НЕ ШИРШЕ (не «весь файл»). Файл на 4 600 рядків приписав би кожну
    правку всім 80 правилам у ньому — число, яке нічого не розрізняє.
    """
    за_правилом = collections.defaultdict(lambda: collections.OrderedDict())
    рядки = [l for l in _git("log", "--reverse", "--format=%H|%h|%ad|%s",
                             "--date=format:%d.%m", "%s..HEAD" % база).splitlines() if l]
    for рядок in рядки:
        повн, корот, дата, тема = рядок.split("|", 3)
        тіло = _git("log", "-1", "--format=%B", повн)
        діф = _git("show", "--format=", "--unified=%d" % контекст, повн).splitlines()
        файл, шматок = None, []
        кошики = dict(код=set(), коментар=set(), документ=set())

        def злити(шм, ф):
            if not ф or not шм:
                return
            дод = [l[1:] for l in шм if l.startswith("+")]
            if not дод:
                return                       # шматок лише зі знятими рядками
            ід_у_шматку = set(ID.findall("\n".join(l[1:] if l[:1] in "+- " else l for l in шм)))
            if not ід_у_шматку:
                return
            if ф.endswith(_КОД):
                # виконуваним вважається шматок, у якому доданий НЕ-коментарний рядок
                кошик = "код" if any(not _КОМЕНТАР.match(l) and l.strip() for l in дод) else "коментар"
            else:
                кошик = "документ"
            кошики[кошик].update(ід_у_шматку)

        for l in діф:
            if l.startswith("+++ "):
                злити(шматок, файл); шматок = []
                _ш = l[4:].strip()
                if _ш.startswith('"') and _ш.endswith('"'):
                    _ш = _ш[1:-1]
                файл = _ш[2:] if _ш.startswith("b/") else _ш
                continue
            if l.startswith("@@"):
                злити(шматок, файл); шматок = []
                continue
            if l.startswith(("---", "diff ", "index ", "similarity", "rename", "new file",
                             "deleted file", "old mode", "new mode", "Binary")):
                continue
            шматок.append(l)
        злити(шматок, файл)

        ід_запис = set(ID.findall(тіло))
        for i in sorted(set().union(*кошики.values()) | ід_запис):
            за_правилом[i][корот] = dict(
                коміт=корот, дата=дата, тема=тема,
                у_коді=i in кошики["код"], у_коментарі=i in кошики["коментар"],
                у_документі=i in кошики["документ"], у_записі=i in ід_запис)
    return {k: list(v.values()) for k, v in за_правилом.items()}


def зібрати(база=БАЗА_ЗА_ЗАМОВЧУВАННЯМ):
    корп = sorted(КР.ід())
    форм = формулювання()
    код = ГД.з_коду(_ТУТ)
    пр = правки(база)
    теми = collections.defaultdict(list)
    for імя, текст in sorted(КР.текст().items()):
        for ід in set(КР.ID_ПРАВИЛА.findall(текст)):
            теми[ід].append(імя.split("_")[0])
    рядки = []
    for ід in sorted(set(корп) | set(пр) | set(код)):
        рід = РР.рід(ід) if hasattr(РР, "рід") else None
        рядки.append(dict(
            правило=ід,
            у_корпусі=ід in корп,
            теми=sorted(теми.get(ід, [])),
            тема_блоку=(форм.get(ід) or ("", ""))[0],
            формулювання=(форм.get(ід) or ("", ""))[1],
            рід=(рід or {}).get("рід") if isinstance(рід, dict) else рід,
            шар=(рід or {}).get("шар") if isinstance(рід, dict) else None,
            мусить_кодом=(рід or {}).get("кодом") if isinstance(рід, dict) else None,
            у_коді=sorted(код.get(ід, [])) if isinstance(код, dict) else [],
            правки=пр.get(ід, [])))
    return рядки


def _мд(рядки):
    з_правками = [r for r in рядки if r["правки"]]
    торкнуто_коду = [r for r in з_правками if any(p["у_коді"] for p in r["правки"])]
    лише_запис = [r for r in з_правками
                  if not any(p["у_коді"] or p["у_коментарі"] for p in r["правки"])]
    вих = ["# ДОВІДНИК ПРАВИЛ: що каже корпус · де в коді · що робила сесія", "",
           "Породжено `джерела/правила.py`. Формулювання — витяг із корпусу, "
           "правки — витяг із git; ані те, ані те не набране руками.", "",
           "| | |", "|---|---:|",
           "| правил у корпусі | %d |" % sum(1 for r in рядки if r["у_корпусі"]),
           "| ID, які код цитує поза корпусом | %d |" % sum(1 for r in рядки if not r["у_корпусі"]),
           "| правил, яких торкнулась сесія | %d |" % len(з_правками),
           "| з них зі зміненим ВИКОНУВАНИМ рядком | %d |" % len(торкнуто_коду),
           "| з них лише в коментарі / документі / записі | %d |" % len(лише_запис), ""]
    за_темою = collections.defaultdict(list)
    for r in рядки:
        за_темою[r["теми"][0] if r["теми"] else "(поза корпусом)"].append(r)
    for тема in sorted(за_темою):
        вих += ["", "## %s — %d правил" % (тема, len(за_темою[тема])), ""]
        for r in за_темою[тема]:
            вих.append("### `%s`%s" % (r["правило"], "" if r["у_корпусі"] else "  ⚠ поза корпусом"))
            if r["формулювання"]:
                вих += ["", "> %s" % r["формулювання"]]
            мета = []
            if r["рід"]: мета.append("рід: %s" % r["рід"])
            if r["шар"]: мета.append("шар: %s" % r["шар"])
            if len(r["теми"]) > 1: мета.append("теми: %s" % ", ".join(r["теми"]))
            мета.append("у коді: %s" % (", ".join(r["у_коді"]) or "—"))
            вих += ["", "· " + " · ".join(мета)]
            if r["правки"]:
                вих += ["", "**правки сесії:**"]
                for p in r["правки"]:
                    мітки = [м for м, к in (("код", "у_коді"), ("коментар", "у_коментарі"),
                                            ("документ", "у_документі"), ("запис", "у_записі"))
                             if p.get(к)]
                    вих.append("- `%s` %s [%s] %s"
                               % (p["коміт"], p["дата"], "+".join(мітки), p["тема"]))
            вих.append("")
    return "\n".join(вих)


if __name__ == "__main__":
    база = БАЗА_ЗА_ЗАМОВЧУВАННЯМ
    if "--база" in sys.argv:
        база = sys.argv[sys.argv.index("--база") + 1]
    рядки = зібрати(база)
