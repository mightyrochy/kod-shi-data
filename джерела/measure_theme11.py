def прогін():
    бачені, спрацювань = {}, {}
    for тип, вар, тіло_ім, темп in itertools.product(
            ТИПИ, ВАРІАНТИ, ТІЛА, ТЕМПЕРАТУРИ):
        речі = _речі(тип, **dict(вар))
        # додаємо жакет і тришаровий каскад у частині прогонів — інакше K-OUT-05
        # і K-OUT-04 не мають конфігурації, у якій узагалі можуть спрацювати
        if вар.get("_жакет_нижче"):
            # жакет визирає З-ПІД пальта: його поділ НИЖЧЕ (ближче до підлоги)
            речі.append(dict(id="жакет", слот="верх", назва="блейзер", hex="#333",
                             площа=0.3, тип="блейзер", низ_см=90.0, край_джерело="річ"))
        if вар.get("_низ_обʼємний"):
            речі[1] = dict(речі[1], слот="низ", назва="штани палацо", крій="палацо")
        if вар.get("низ_см") == 50.0:
            речі.append(dict(id="жакет", слот="верх", назва="блейзер", hex="#333",
                             площа=0.3, тип="блейзер", низ_см=53.0, край_джерело="річ"))
        if вар.get("низ_см") == 47.9:
            речі.append(dict(id="сорочка", слот="верх", назва="сорочка", hex="#eee",
                             площа=0.3, низ_см=45.0, край_джерело="річ"))
            речі[1] = dict(речі[1], низ_см=42.0, край_джерело="річ")
        if вар.get("_каскад") == "правильний":
            # пальто НАЙДОВШЕ (край найнижчий), з-під нього сорочка, з-під неї сукня
            речі.append(dict(id="сорочка", слот="верх", назва="сорочка", hex="#eee",
                             площа=0.3, низ_см=45.0, край_джерело="річ"))
            низ = {k: v for k, v in речі[1].items() if k != "довжина_рівень"}
            речі[1] = dict(низ, низ_см=48.0, край_джерело="річ")
        if вар.get("_близнюк"):
            # сукня дістає ВИМІРЯНИЙ край і втрачає «довжина_рівень»: інакше
            # край_см візьме висоту коліна на тілі й |Δ| перестане бути 7 см
            низ = {k: v for k, v in речі[1].items() if k != "довжина_рівень"}
            речі[1] = dict(низ, край_джерело="річ",
                           низ_см=53.0 if вар["_близнюк"] == "верхній коротший" else 60.0)
        _СЛ.почати()
        рез = ВШ.перевірити(речі, тіло=ТІЛА[тіло_ім], темп_c=темп, вітер=True,
                            реагенти=True, тривалість_год=2.0)
        for кл in ("ворота", "преференції", "питання", "ремонти", "команди"):
            for з in рез.get(кл) or []:
                п = з.get("правило")
                if not п:
                    continue
                спрацювань[п] = спрацювань.get(п, 0) + 1
                бачені.setdefault(п, set()).add("%s·%s·%s" % (тип, тіло_ім, темп))
        for п in _СЛ.ід_у_сліді():
            спрацювань.setdefault(п, 0)
            бачені.setdefault(п, set())
    return бачені, спрацювань


def корпусні(шлях="тема-11_верхній-шар.md"):
    import re
    txt = open(шлях, encoding="utf-8").read()
    усі = set(re.findall(r"\b(K-OUT-\d\d)\b", txt))
    # K-OUT-37 скасовано й злито в K-OUT-12: ID більше не емітується (частина XXI)
    return усі - {"K-OUT-37"}


