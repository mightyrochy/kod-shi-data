def _речі(тип, **атр):
    в = dict(id="верхній", слот="верхній_шар", назва="верхній шар", hex="#3a3a3a",
             площа=0.5, near=0.6, тип=тип, тип_верхнього=тип)
    атр = {k: v for k, v in атр.items() if not k.startswith("_")}
    в.update(атр)
    return [в,
            dict(id="сукня", слот="сукня", назва="сукня", hex="#8a6d4f", площа=0.5,
                 near=0.85, довжина_рівень=атр.pop("_поділ", "коліно")),
            dict(id="взуття", слот="взуття", назва="черевики", hex="#222", площа=0.08)]


