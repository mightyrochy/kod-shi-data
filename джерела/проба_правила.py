def прогнати(ід=None):
    F, T = _особа(), _тіло()
    обрані = [в for в in ВИПАДКИ if not ід or в["ід"] in ід]
    for в in обрані:
        print("\n" + "═" * 78)
        print("%s   %s" % (в["ід"], в["вимога"]))
        print("─" * 78)
        print("вхід: " + " · ".join(
            "%s %s%s" % (r["слот"], r.get("тип") or r["hex"],
                         (" " + r["hex"]) if r.get("тип") else "")
            for r in в["речі"]))
        сц = dict(в["сцен"])
        print("сцена: " + (", ".join("%s=%s" % (k, v) for k, v in сц.items()) or "—"))
        try:
            вих = PL.перевірити_образ(F, _з_площами(в["речі"], T), тіло=T, **сц)
        except Exception as e:
            print("  ⛔ ПАДІННЯ: %s: %s" % (type(e).__name__, e))
            continue
        пари = ЗН.без_повторів(ЗН.усі(вих))
        свої = [(ш, z) for ш, z in пари if str(z.get("правило", "")).startswith(в["ід"])]
        if not свої:
            інші = sorted({str(z.get("правило")) for _, z in пари})
            print("  МОВЧИТЬ. Вийшли натомість: %s" % (", ".join(інші[:14]) or "нічого"))
            continue
        for ш, z in свої:
            # `сила` (hard/strong/soft) живе у знахідці ДО `для_стиліста`; після
            # нього лишається неперервна `сила_нп` із `джерело_сили`. Друкуються
            # обидві: перший прогін показав «сила None» усюди й ледь не був
            # записаний у дефект — а це просто інше поле.
            print("  ✔ %s · сила %s · нп %s · регістр %s · блокує %s"
                  % (z.get("правило"), z.get("сила") or "—", z.get("сила_нп"),
                     z.get("регістр"), z.get("блокує")))
            if z.get("джерело_сили"):
                print("     джерело сили: %s" % z["джерело_сили"])
            if z.get("поріг"):
                print("     поріг: %s" % z["поріг"])
            print("     шлях: %s" % ш)
            print("     суть: %s" % str(z.get("суть"))[:150])
            if z.get("чому"):
                print("     чому: %s" % str(z.get("чому"))[:200])
            # `ремонт` у знахідці, `ремонти` після `для_стиліста` — знову два імені
            # на одне поле; проба друкує обидва, щоб не «загубити» ремонт мовчки.
            р = z.get("ремонти") or z.get("ремонт")
            if р:
                print("     ремонт: %s" % ("; ".join(р) if isinstance(р, list) else str(р))[:170])
            if z.get("вікно"):
                print("     вікно в каталог: %s" % str(z["вікно"])[:170])
            for k in ("ламається", "де_ламається"):
                if z.get(k):
                    print("     ламається: %s" % str(z[k])[:170])


if __name__ == "__main__":
    прогнати(sys.argv[1:] or None)
