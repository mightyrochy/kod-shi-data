def річ(слот, hex_, **поля):
    """Річ у тому вигляді, в якому її бачить суддя. Довжини задані навмисно:
    без них шар посадки мовчить і половина проб нічого не показує."""
    д = dict(id=поля.pop("id", слот), слот=слот, hex=hex_, назва=поля.pop("назва", слот))
    д.setdefault("верх_см", {"верх": 140, "низ": 100, "сукня": 140,
                             "взуття": 12, "сумка": 105, "верхній_шар": 145,
                             "шарф": 145, "прикраси": 140}.get(слот, 100))
    д.setdefault("низ_см", {"верх": 95, "низ": 5, "сукня": 55,
                            "взуття": 0, "сумка": 95, "верхній_шар": 60,
                            "шарф": 120, "прикраси": 130}.get(слот, 50))
    д.update(поля)
    return д


def _з_площами(речі, T):
    """Дати речам ВИМІРЯНУ площу — інакше проба показує «мовчить» там, де правило справне.

    ЗНАЙДЕНО ПЕРШИМ ПРОГОНОМ (08.09.2026). Одинадцять із вісімнадцяти правил
    промовчали, і виглядало це як «колірний шар мертвий». Насправді суддя чесно
    УТРИМАВСЯ: без площі він виносить одну знахідку «площі не виміряні» і називає
    в ній поіменно п'ять правил, яких не судитиме (K-COL-01, K-COL-02, K-COMP-03,
    K-COL-05, K-COL-06). Тобто мовчав не код, а проба: вона подавала неповний вхід.

    Це і є той випадок, заради якого проба взагалі писалась. Читанням коду я б
    записав п'ять справних правил у зламані.
    """
    гео = {г["id"]: г for г in areas.образ_з_геометрії(
        T["профіль"], [dict(id=r["id"], верх_см=r["верх_см"], низ_см=r["низ_см"],
                            припуск=r.get("припуск", "straight")) for r in речі])}
    out = []
    for r in речі:
        г = гео[r["id"]]
        out.append(dict(r, площа=г["площа"], near=г["near"], джерело_площі="геометрія"))
    return out


