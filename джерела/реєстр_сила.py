def _ранг(сила):
    """Місце сили на ЄДИНІЙ шкалі `ПОРЯДОК`: чим сильніша, тим більший ранг
    (hard = 5 … hint = 1). Невідома сила — «питання», «утримано», «ok», None —
    дає None, а НЕ мовчазний 0.

    ЗНАЙДЕНО Н-outfit-2-090: `обмежити_слабшу_вісь` тримала власний
    чотирирівневий словник сил без "default". Наслідок був подвійний: знахідка
    силою `default` давала стелю 0 (бо `.get(…, 0)`), а пошук імені сили за
    значенням 0 не знаходив нічого і кидав IndexError, який вбивав увесь
    `review()`. Мовчазний 0 однаково небезпечний і для сил поза шкалою: вони
    мають виводити групу З-ПІД обмеження, а не зрізати сусіда до найслабшого.
    Тому шкала одна й повертає None, коли не знає сили."""
    try:
        return len(ПОРЯДОК) - ПОРЯДОК.index(сила)
    except ValueError:
        return None
def _сила(база, вимір, поріг, розкид=None):
    """Сила ≤ верифікація. Поріг некалібрований -> вердикт біля порога не заслуговує
    повної сили правила.

    ДОДАНО ПІСЛЯ ПЕРШОГО РЕАЛЬНОГО ФОТО: маржа рішення має перевищувати ТОЧНІСТЬ
    ВИМІРУ. На дзеркальному селфі та сама спідниця дала L*29.9 у одному місці й
    L*43.3 в іншому — розкид 13 при пороzі кроку світлоти 12. Тобто вердикт залежав
    від того, куди впала маска. Це не другий фольклорний поріг: тут порівнюються дві
    ВИМІРЯНІ величини — маржа рішення проти розкиду зони (extract.zone_stats рахував
    його з самого початку, і досі ним ніхто не користувався)."""
    смуга = abs(поріг) * C["band"] or 1.0
    маржа = abs(вимір - поріг)
    if розкид and маржа < розкид:      # `розкид` тут = ПОХИБКА ОЦІНКИ (se_L), не MAD пікселів
        i = min(ПОРЯДОК.index(база) + 1, len(ПОРЯДОК) - 1)
        return ПОРЯДОК[i], (f"рішення тонше за точність виміру (маржа {маржа:.0f} < "
                            f"розкид зони {розкид:.0f}) — знижено")
    if маржа < смуга:
        i = min(ПОРЯДОК.index(база) + 1, len(ПОРЯДОК) - 1)
        return ПОРЯДОК[i], f"межовий випадок (|{вимір:.0f}−{поріг:.0f}| < {смуга:.0f}) — знижено"
    return база, None

def _репліка(суть, чому):
    """Переклад знахідки з мови вироку в мову спостереження для стиліста-моделі.
    Не «порушено правило X», а «я бачу ось це, ось наскільки виразно» — рішення за
    композитором. Тон описовий: називає видиме, не приписує помилки."""
    основа = суть.split(" — ")[0] if " — " in суть else суть
    основа = основа[0].upper() + основа[1:]
    # `правило` і `впевненість` прибрано з сигнатури: обидва вже їдуть окремими
    # полями знахідки, а тут лише вдавали, що впливають на формулювання.
    return f"{основа}. {чому}"

def _мʼякший_ремонт(ремонт):
    """Ремонт репліки — пропозиція, не імператив. Список лишається (він корисний
    композиторові як напрям пошуку), але подається як опція."""
    if isinstance(ремонт, str):
        return "як варіант — " + ремонт[0].lower() + ремонт[1:]
    return ["як варіанти:"] + ремонт

