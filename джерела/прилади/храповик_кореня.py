"""ХРАПОВИК КОРЕНЯ: число місць кореня на голові не вище, ніж на базі (робота CI `khrapovyk.yml`).

ЧОМУ. Корінь — одна справа з паспортом `аудит/корені/<корінь>.md`; місця кореня лічить прилад, якого не писала
сесія, що лагодить (ядро, «Причини»). Без храповика число тримала пам'ять сесій: власна проба виконавця бачила
частину місць, яку лічить прилад перевірки.

ФОРМАТ ПАСПОРТА (`аудит/КОД.md`). Рядок `прилад: <шлях від кореня репозиторію> [аргументи]` — з початку рядка, один
на паспорт; `база: <шлях>[, <шлях>…]` — дані, з якими прилад звіряє, і модулі, які `.py`-прилад імпортує зі своєї теки
чи `джерела/прилади/` (файли чи теки). Рядок, схожий на них (після двокрапки шлях: «/» чи розширення файлу), але не з
початку рядка чи не тим регістром, — червоний; проза на «Прилад»/«База» без шляху — ні. Прилад друкує
останнім непорожнім рядком stdout `місць: <N>` і виходить з кодом 0; `.py` іде через python, `.js`/`.mjs` — node,
`.sh` — bash, решта — як виконуваний файл; робоча тека — корінь дерева.

ЩО РОБИТЬ. Голова — робоче дерево `--репо` (у CI — checkout події: для PR це коміт злиття з базою), база — `--база`
(push — `event.before`). Для PR з `--пр` база — перший батько коміту злиття, тобто той `main`, з яким голову злито:
`pull_request.base.sha` лишається давнім, якщо PR влив свіжий `main`, і різниця з ним — це все, що `main` набрав
відтоді, а не зміни PR (дошка 11353); голова не є комітом злиття — база з `--база`. Для кожного кореня лічить прилад за рядком ГОЛОВИ (рядок знято
чи паспорт видалено — за рядком бази) на дереві голови й на дереві бази (окремий `git worktree`, у який покладено
прилад і `база:` голови): так зміна самого приладу не рахується як зміна коду. Голова > база — червоний «корінь
<ім'я>: місць <база> → <голова>»; однаково чи менше — зелений, число в підсумку. Прилад без `місць:` чи з кодом ≠ 0
на будь-якому дереві — червоний з іменем кореня. Клас приладу — файли `прилад:` і `база:`, імпортовані помічники,
рядки `прилад:`/`база:` паспорта (на базі й голові) і сам храповик (`ХРАПОВИК`); зміна класу разом з іншим файлом
`джерела/` чи `показ/` (різниця дерев бази й голови) — червоний «прилад і виправлення — різними PR», сама — зелений
з рядком. Паспорт без `прилад:` — пропуск із рядком; коренів з приладом 0 — зелений. Повноти приладу не оцінює (це
перевірка), корінь без паспорта ні на голові, ні на базі не міряє.

ОБСЯГ І ДИФФ (`--пр`). Корінь на PR лічиться лише коли дифф PR перетинає його обсяг: файли `прилад:`, `база:`, аргументів
рядка, імпортовані помічники, паспорт — і шляхи, названі в коді приладу й помічників (рядкові сталі: шлях, ланцюг
`os.path.join`/`Path`/`/`, тека, ім'я файлу; без докстрінгів, а з голих імен тек лише ті, що не стоять у колекції для
`in`/`not in`, тобто не є фільтром виключення; `__file__` — ще й тека над текою приладу). Обсяг не визначено (прилад не
`.py`, не розібрано чи без жодного шляху), зачеплено храповик (код, стенд, workflow), чи це push у `main` без `--пр` —
корінь лічиться, як раніше. Корінь поза диффом — у звіті рядок «поза диффом»; місць у ньому не лічено, і рости їм
нема від чого: дифф не торкає нічого, що прилад читає. Обсяг з коду приладу — наближення, а не доказ: push у `main`
лічить усі корені, тож пропущений ріст червонить там (стенд: обсяг, знятий з коду, ⊇ файли, відкриті приладом).

ЗАПУСК (з кореня репозиторію):
    python3 джерела/прилади/храповик_кореня.py --база <SHA>        # база порожня чи нулі — пропуск із рядком
    python3 джерела/прилади/храповик_кореня.py --пр --база <SHA>   # PR: база — перший батько коміту злиття
Підсумок — stdout і `$GITHUB_STEP_SUMMARY`; код виходу 1 — є червоний. Стенд — `стенд_храповика_кореня.py`.
"""
