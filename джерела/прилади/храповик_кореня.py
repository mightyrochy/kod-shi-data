СХОЖИЙ = re.compile(r'^[\s>*_`#-]*(прилад|база)[*_`]*\s*:[\s*_`]*(?=[^\s`]*(?:/|\.\w+(?:[\s`.,;:)]|$)))', re.IGNORECASE)
МІСЦЬ = re.compile(r'^місць:\s*(\d+)\s*$')
