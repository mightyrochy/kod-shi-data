# -*- coding: utf-8 -*-
"""ХРАПОВИК КОРЕНЯ: число місць кореня на голові не вище, ніж на базі (робота CI `khrapovyk.yml`).

ЧОМУ. Корінь — одна справа з паспортом `аудит/корені/<корінь>.md`; місця кореня лічить прилад, якого не писала
сесія, що лагодить (ядро, «Причини»). Без храповика число тримала пам'ять сесій: власна проба виконавця бачила
частину місць, яку лічить прилад перевірки.

ФОРМАТ ПАСПОРТА (`аудит/КОД.md`). Рядок `прилад: <шлях від кореня репозиторію> [аргументи]` — з початку рядка, один
на паспорт; `база: <шлях>[, <шлях>…]` — дані, з якими прилад звіряє, і модулі, які `.py`-прилад імпортує зі своєї теки
чи `джерела/прилади/` (файли чи теки). Рядок, схожий на них, але не з початку рядка, — червоний. Прилад друкує
останнім непорожнім рядком stdout `місць: <N>` і виходить з кодом 0; `.py` іде через python, `.js`/`.mjs` — node,
`.sh` — bash, решта — як виконуваний файл; робоча тека — корінь дерева.

ЩО РОБИТЬ. Голова — робоче дерево `--репо` (у CI — checkout події: для PR це коміт злиття з базою), база — `--база`
(PR — `pull_request.base.sha`, push — `event.before`). Для кожного кореня лічить прилад за рядком ГОЛОВИ (рядок знято
чи паспорт видалено — за рядком бази) на дереві голови й на дереві бази (окремий `git worktree`, у який покладено
прилад і `база:` голови): так зміна самого приладу не рахується як зміна коду. Голова > база — червоний «корінь
<ім'я>: місць <база> → <голова>»; однаково чи менше — зелений, число в підсумку. Прилад без `місць:` чи з кодом ≠ 0
на будь-якому дереві — червоний з іменем кореня. Клас приладу — файли `прилад:` і `база:`, імпортовані помічники,
рядки `прилад:`/`база:` паспорта (на базі й голові) і сам храповик (`ХРАПОВИК`); зміна класу разом з іншим файлом
`джерела/` чи `показ/` (різниця дерев бази й голови) — червоний «прилад і виправлення — різними PR», сама — зелений
з рядком. Паспорт без `прилад:` — пропуск із рядком; коренів з приладом 0 — зелений. Повноти приладу не оцінює (це
перевірка), корінь без паспорта ні на голові, ні на базі не міряє.

ЗАПУСК (з кореня репозиторію):
    python3 джерела/прилади/храповик_кореня.py --база <SHA>        # база порожня чи нулі — пропуск із рядком
Підсумок — stdout і `$GITHUB_STEP_SUMMARY`; код виходу 1 — є червоний. Стенд — `стенд_храповика_кореня.py`.
"""
import argparse
import ast
import os
import posixpath
import re
import shlex
import shutil
import subprocess
import sys
import tempfile

ТЕКА_КОРЕНІВ = 'аудит/корені'
ЗАХИЩЕНІ = ('джерела/', 'показ/')
ХРАПОВИК = ('.github/workflows/khrapovyk.yml', 'джерела/прилади/храповик_кореня.py',
            'джерела/прилади/стенд_храповика_кореня.py')
ТЕКА_ПРИЛАДІВ = 'джерела/прилади'
ПРИЛАД = re.compile(r'^прилад:\s*(.*?)\s*$')
БАЗА = re.compile(r'^база:\s*(.*?)\s*$')
СХОЖИЙ = re.compile(r'^[\s>*_`#-]*(прилад|база)[*_`]*\s*:', re.IGNORECASE)
МІСЦЬ = re.compile(r'^місць:\s*(\d+)\s*$')
ЧАС_ПРИЛАДУ = 900


def git(репо, *аргументи, байти=False):
    """Виконує git у репозиторії й повертає stdout (текст чи байти); помилка — виняток."""
    вихід = subprocess.run(['git', '-C', репо, '-c', 'core.quotepath=off', *аргументи],
                           capture_output=True, check=True)
    return вихід.stdout if байти else вихід.stdout.decode('utf-8')


def без_лапок(значення):
    """Знімає одну пару зворотних лапок навколо значення рядка паспорта."""
    if len(значення) >= 2 and значення[0] == значення[-1] == '`':
        return значення[1:-1].strip()
    return значення


def шлях_у_дереві(шлях):
    """Шлях від кореня репозиторію без виходу за нього; None — недопустимий."""
    шлях = шлях.strip().strip('`').strip()
    if not шлях or os.path.isabs(шлях):
        return None
    чистий = os.path.normpath(шлях).replace(os.sep, '/')
    return None if чистий == '..' or чистий.startswith('../') or чистий == '.' else чистий


def розібрати_паспорт(текст):
    """Читає рядки «прилад:» і «база:»; → (прилад, аргументи, бази, помилки), прилад None — рядка нема.

    Рядок, схожий на них не з початку чи не тим регістром (`- прилад:`, `**прилад:**`, `Прилад:`), — помилка, а не
    пропуск: опечатка формату мовчки вимикала б корінь.
    """
    прилади, бази, помилки = [], [], []
    for рядок in текст.splitlines():
        if (м := ПРИЛАД.match(рядок)):
            прилади.append(без_лапок(м.group(1)))
        elif (м := БАЗА.match(рядок)):
            бази.extend(ч for ч in без_лапок(м.group(1)).split(',') if ч.strip())
        elif СХОЖИЙ.match(рядок):
            помилки.append(f'рядок «{рядок.strip()[:60]}» — не формат «прилад:»/«база:» з початку рядка (аудит/КОД.md)')
    if not прилади:
        return None, [], [], помилки
    if len(прилади) > 1:
        помилки.append(f'рядків «прилад:» {len(прилади)}, має бути один')
    try:
        слова = shlex.split(прилади[0])
    except ValueError as е:
        return '', [], [], помилки + [f'рядок «прилад:» не розібрано: {е}']
    if not слова:
        return '', [], [], помилки + ['рядок «прилад:» порожній']
    прилад = шлях_у_дереві(слова[0])
    if прилад is None:
        помилки.append(f'шлях приладу «{слова[0]}» — не шлях від кореня репозиторію')
    чисті_бази = []
    for б in бази:
        ч = шлях_у_дереві(б)
        if ч is None:
            помилки.append(f'шлях бази «{б.strip()}» — не шлях від кореня репозиторію')
        else:
            чисті_бази.append(ч)
    return прилад or '', слова[1:], чисті_бази, помилки


def рядки_приладу(текст):
    """Рядки паспорта, що задають прилад (`прилад:`, `база:` і схожі на них), — для звірки бази й голови."""
    return tuple(р.strip() for р in (текст or '').splitlines()
                 if ПРИЛАД.match(р) or БАЗА.match(р) or СХОЖИЙ.match(р))


def помічники(читати, прилад):
    """Модулі, які `.py`-прилад імпортує зі своєї теки чи `джерела/прилади/`, разом із їхніми імпортами.

    `читати(шлях)` дає текст файлу дерева чи None. Помічник лічить разом із приладом, тож теж мусить бути в `база:`:
    інакше на дереві бази він береться з бази, а його зміна з кодом не червонить «різними PR».
    """
    знайдені, черга = set(), [прилад] if прилад.endswith('.py') else []
    while черга:
        шлях = черга.pop()
        try:
            дерево = ast.parse(читати(шлях) or '')
        except SyntaxError:
            continue
        імена = set()
        for вузол in ast.walk(дерево):
            if isinstance(вузол, ast.Import):
                імена.update(а.name.split('.')[0] for а in вузол.names)
            elif isinstance(вузол, ast.ImportFrom) and not вузол.level and вузол.module:
                імена.add(вузол.module.split('.')[0])
        for імя in sorted(імена):
            for тека in dict.fromkeys([os.path.dirname(прилад), ТЕКА_ПРИЛАДІВ]):
                модуль = posixpath.join(тека, імя)
                for кандидат, файл in ((модуль + '.py', модуль + '.py'), (модуль, модуль + '/__init__.py')):
                    if кандидат not in знайдені and кандидат != прилад and читати(файл) is not None:
                        знайдені.add(кандидат)
                        черга.append(файл)
    return знайдені


def паспорти_голови(репо):
    """Паспорти з робочого дерева: {ім'я кореня: текст}; теки нема — порожньо."""
    тека = os.path.join(репо, ТЕКА_КОРЕНІВ)
    if not os.path.isdir(тека):
        return {}
    паспорти = {}
    for імя in sorted(os.listdir(тека)):
        if імя.endswith('.md') and os.path.isfile(os.path.join(тека, імя)):
            with open(os.path.join(тека, імя), encoding='utf-8') as ф:
                паспорти[імя[:-3]] = ф.read()
    return паспорти


def паспорти_бази(репо, база):
    """Паспорти з коміту бази: {ім'я кореня: текст}."""
    паспорти = {}
    for шлях in git(репо, 'ls-tree', '-z', '--name-only', база, '--', ТЕКА_КОРЕНІВ + '/').split('\0'):
        if шлях.endswith('.md'):
            імя = шлях.rsplit('/', 1)[-1][:-3]
            паспорти[імя] = git(репо, 'show', f'{база}:{шлях}')
    return паспорти


def під(шлях, межа):
    """Чи шлях — сам файл межі або лежить у теці межі."""
    return шлях == межа or шлях.startswith(межа.rstrip('/') + '/')


def команда(прилад, аргументи):
    """Команда запуску приладу за розширенням файлу."""
    if прилад.endswith('.py'):
        return [sys.executable, прилад, *аргументи]
    if прилад.endswith(('.js', '.mjs')):
        return ['node', прилад, *аргументи]
    if прилад.endswith('.sh'):
        return ['bash', прилад, *аргументи]
    return ['./' + прилад, *аргументи]


def лічити(дерево, прилад, аргументи):
    """Запускає прилад у дереві; → (число, None) або (None, причина червоного)."""
    if not os.path.isfile(os.path.join(дерево, прилад)):
        return None, f'файлу {прилад} нема'
    середовище = dict(os.environ, PYTHONDONTWRITEBYTECODE='1')
    середовище.pop('GITHUB_STEP_SUMMARY', None)
    try:
        вихід = subprocess.run(команда(прилад, аргументи), cwd=дерево, capture_output=True,
                               timeout=ЧАС_ПРИЛАДУ, env=середовище)
    except subprocess.TimeoutExpired:
        return None, f'не закінчив за {ЧАС_ПРИЛАДУ} с'
    except OSError as е:
        return None, f'не запустився: {е}'
    рядки = [р for р in вихід.stdout.decode('utf-8', 'replace').splitlines() if р.strip()]
    if вихід.returncode != 0:
        хвіст = вихід.stderr.decode('utf-8', 'replace').strip().splitlines()[-3:]
        return None, f'код виходу {вихід.returncode}' + (f' ({" / ".join(хвіст)})' if хвіст else '')
    м = МІСЦЬ.match(рядки[-1].strip()) if рядки else None
    if not м:
        хвіст = f' («{рядки[-1].strip()[:80]}»)' if рядки else ' (вивід порожній)'
        return None, 'останній рядок не «місць: <N>»' + хвіст
    return int(м.group(1)), None


def покласти(з, до, шлях):
    """Копія файлу чи теки голови в дерево бази (тека бази замінюється цілком)."""
    джерело, ціль = os.path.join(з, шлях), os.path.join(до, шлях)
    if os.path.isdir(ціль) and not os.path.islink(ціль):
        shutil.rmtree(ціль)
    elif os.path.lexists(ціль):
        os.remove(ціль)
    os.makedirs(os.path.dirname(ціль) or до, exist_ok=True)
    if os.path.isdir(джерело):
        shutil.copytree(джерело, ціль, symlinks=True)
    else:
        shutil.copy2(джерело, ціль)


def покласти_тимчасово(з, до, шлях, створені):
    """Копія файлу бази в дерево голови, де його нема; найвищу створену теку чи файл пише в `створені`."""
    верх = шлях
    while os.path.dirname(верх) and not os.path.exists(os.path.join(до, os.path.dirname(верх))):
        верх = os.path.dirname(верх)
    створені.append(os.path.join(до, верх))
    покласти(з, до, шлях)


def змінені_файли(репо, база):
    """Шляхи, якими дерево голови відрізняється від коміту бази (зокрема нові невідстежені файли).

    Різниця дерев, а не історії: у CI голова PR — коміт злиття з базою, тож різниця — рівно зміни PR, і неглибокого
    клону досить.
    """
    вихід = git(репо, 'diff', '--name-only', '--no-renames', '-z', база, байти=True).decode('utf-8')
    нові = git(репо, 'ls-files', '--others', '--exclude-standard', '-z')
    return {ш for ш in (вихід + нові).split('\0') if ш}


def храповик(репо, база):
    """Лічить корені на голові й базі та звіряє зміни; → (рядки підсумку, червоні).

    Прилад кореня — файл `прилад:`, файли `база:`, помічники, яких прилад імпортує, і самі рядки `прилад:`/`база:`
    паспорта; храповик (код, стенд, workflow) — теж у класі. Зміна класу разом з іншим файлом `джерела/` чи `показ/` —
    червоний. Корінь, рядок приладу якого знято на голові чи паспорт видалено, лічиться рядком бази, а не пропускається.
    """
    рядки, червоні = [], []
    паспорти = паспорти_голови(репо)
    розібрані, пропущені = {}, []
    for імя, текст in паспорти.items():
        прилад, аргументи, бази, помилки = розібрати_паспорт(текст)
        if помилки:
            червоні.append(f'корінь {імя}: паспорт — {"; ".join(помилки)}')
        elif прилад is None:
            пропущені.append(імя)
        else:
            розібрані[імя] = (прилад, аргументи, бази)
    рядки.append(f'коренів з приладом: {len(розібрані)}')

    if not база or not база.strip('0'):
        рядки += [f'корінь {імя}: рядка «прилад:» нема — пропущено' for імя in пропущені]
        рядки.append('бази нема (ручний запуск чи нова гілка) — храповик пропущено, див. 10720')
        return рядки, червоні
    try:
        база = git(репо, 'rev-parse', '--verify', '-q', база + '^{commit}').strip()
    except subprocess.CalledProcessError:
        червоні.append(f'базу {база} не знайдено в репозиторії — порівняти нема з чим')
        return рядки, червоні

    def читати_голову(шлях):
        """Текст файлу робочого дерева голови чи None."""
        повний = os.path.join(репо, шлях)
        return open(повний, encoding='utf-8', errors='replace').read() if os.path.isfile(повний) else None

    def читати_базу(шлях):
        """Текст файлу з коміту бази чи None."""
        try:
            return git(репо, 'show', f'{база}:{шлях}')
        except (subprocess.CalledProcessError, UnicodeDecodeError):
            return None

    паспорти_б = паспорти_бази(репо, база)
    розібрані_б = {}
    for імя, текст in паспорти_б.items():
        п, а, б, помилки = розібрати_паспорт(текст)
        if п and not помилки:
            розібрані_б[імя] = (п, а, б)

    # Що лічити: рядок голови; знято чи паспорт видалено — рядок бази.
    рядки += [f'корінь {імя}: рядка «прилад:» нема — пропущено' for імя in пропущені if імя not in розібрані_б]
    корені = dict(розібрані)
    for імя in sorted(set(розібрані_б) - set(розібрані)):
        корені[імя] = розібрані_б[імя]
        причина = 'паспорт видалено' if імя not in паспорти else 'рядок «прилад:» знято чи зіпсовано'
        рядки.append(f'корінь {імя}: на голові {причина} — лічено рядком бази')

    # Правило 3: клас приладу — окремим PR від коду.
    клас = set(ХРАПОВИК)
    змінені_рядки = []
    for імя in sorted(set(паспорти) | set(паспорти_б)):
        if рядки_приладу(паспорти.get(імя)) != рядки_приладу(паспорти_б.get(імя)):
            змінені_рядки.append(f'{ТЕКА_КОРЕНІВ}/{імя}.md (рядки «прилад:»/«база:»)')
            рядки.append(f'корінь {імя}: рядки «прилад:»/«база:» на голові інші, ніж на базі — зміна приладу')
    for (джерело, читати) in ((розібрані, читати_голову), (розібрані_б, читати_базу)):
        for (прилад, _, бази) in джерело.values():
            клас.update([прилад, *бази, *помічники(читати, прилад)])
    for імя, (прилад, _, бази) in корені.items():
        читати = читати_голову if читати_голову(прилад) is not None else читати_базу
        поза = sorted(п for п in помічники(читати, прилад) if not any(під(п, б) for б in бази))
        if поза:
            червоні.append(f'корінь {імя}: прилад {прилад} імпортує {", ".join(поза)} — назви в «база:» паспорта')
    змінені = змінені_файли(репо, база)
    зачеплені = sorted(ш for ш in змінені if any(під(ш, м) for м in клас)) + змінені_рядки
    код = sorted(ш for ш in змінені if ш.startswith(ЗАХИЩЕНІ) and not any(під(ш, м) for м in клас))
    if зачеплені and код:
        червоні.append('прилад і виправлення — різними PR: прилад, база чи храповик ' + ', '.join(зачеплені)
                       + '; разом із ' + ', '.join(код[:10]) + (f' і ще {len(код) - 10}' if len(код) > 10 else ''))
    if not корені:
        return рядки, червоні

    дерево_бази = tempfile.mkdtemp(prefix='храповик_база_')
    створені = []
    try:
        git(репо, 'worktree', 'add', '--detach', '--force', дерево_бази, база)
        нема = {}
        for імя, (прилад, _, бази) in корені.items():
            for шлях in [прилад, *бази]:
                if os.path.lexists(os.path.join(репо, шлях)):
                    покласти(репо, дерево_бази, шлях)
                elif os.path.lexists(os.path.join(дерево_бази, шлях)):
                    покласти_тимчасово(дерево_бази, репо, шлях, створені)
                else:
                    нема.setdefault(імя, []).append(шлях)
        for імя, (прилад, аргументи, бази) in корені.items():
            if імя in нема:
                червоні.append(f'корінь {імя}: файлу приладу чи бази нема ні на голові, ні на базі — '
                               + ', '.join(нема[імя]))
                continue
            на_голові, чому_г = лічити(репо, прилад, аргументи)
            на_базі, чому_б = лічити(дерево_бази, прилад, аргументи)
            if чому_г or чому_б:
                червоні += [f'корінь {імя}: прилад {прилад} на дереві {де} — {чому}'
                            for де, чому in (('голови', чому_г), ('бази', чому_б)) if чому]
            elif на_голові > на_базі:
                червоні.append(f'корінь {імя}: місць {на_базі} → {на_голові}')
            else:
                рядки.append(f'корінь {імя}: місць {на_базі} → {на_голові}')
    finally:
        for шлях in reversed(створені):
            if os.path.isdir(шлях) and not os.path.islink(шлях):
                shutil.rmtree(шлях, ignore_errors=True)
            elif os.path.lexists(шлях):
                os.remove(шлях)
        subprocess.run(['git', '-C', репо, 'worktree', 'remove', '--force', дерево_бази], capture_output=True)
        shutil.rmtree(дерево_бази, ignore_errors=True)
    return рядки, червоні


def main():
    """Запуск з командного рядка: підсумок у stdout і `$GITHUB_STEP_SUMMARY`, код 1 — є червоний."""
    розбір = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    розбір.add_argument('--база', required=True, help='SHA бази; порожньо чи нулі — пропуск із рядком')
    розбір.add_argument('--репо', default='.', help='робоче дерево голови (типово — поточна тека)')
    а = розбір.parse_args()
    репо = git(os.path.abspath(а.репо), 'rev-parse', '--show-toplevel').strip()
    рядки, червоні = храповик(репо, а.база.strip())
    підсумок = ['### храповик кореня', ''] + [f'- ЧЕРВОНИЙ {р}' for р in червоні] + [f'- {р}' for р in рядки]
    підсумок.append('')
    підсумок.append(f'**{"червоний" if червоні else "зелений"}**: червоних {len(червоні)}')
    print('\n'.join(підсумок))
    if os.environ.get('GITHUB_ACTIONS') == 'true':
        for р in червоні:
            print(f'::error title=храповик кореня::{р}')
    if os.environ.get('GITHUB_STEP_SUMMARY'):
        with open(os.environ['GITHUB_STEP_SUMMARY'], 'a', encoding='utf-8') as ф:
            ф.write('\n'.join(підсумок) + '\n')
    return 1 if червоні else 0


if __name__ == '__main__':
    sys.exit(main())
