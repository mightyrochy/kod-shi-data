# -*- coding: utf-8 -*-
"""ОБСЯГ ПРИЛАДУ: прилад кореня, що не прочитав частину обсягу, називає її в stderr і виходить з кодом 1.

ЧОМУ (Д10, `аудит/корені/Приховані-перелік-д.md`). Храповик кореня (`храповик_кореня.py`) зелений, коли місць на
голові однаково чи менше. Прилад, що пропускав нерозбірний файл (`except SyntaxError: continue`) чи модуль, який не
імпортувався, лічив менше й виходив 0 — зменшення від «не бачу» не відрізнялось від «виправлено» (31.10: е2_межі
98 → 69, річ_колір_межі 373 → 258, е2_промпти 123 → 105 при зеленому `py_compile`). Код ≠ 0 храповик уже червонить.

ЯК. Прилад імпортує цей модуль (він — помічник приладу, тож стоїть у `база:` паспорта) і там, де частину обсягу не
прочитано, кличе `непрочитано(що, причина)` замість мовчазного пропуску; `розібрати(текст, шлях)` — `ast.parse`, що
нерозбірний файл записує сам. Наприкінці процесу (`atexit`), якщо записане є, модуль друкує в stderr перелік і
останнім рядком — скільки частин не прочитано, і завершує процес кодом 1, хоч би як прилад виходив (`return 0`,
`sys.exit(0)`, кінець модуля): так механізм один на всі прилади, а не перевірка коду в кожному `main`. Рядок
`місць: <N>` прилад друкує як і раніше — число видно людині, але храповик його не бере, бо код ≠ 0.

Обсяг, який прилад свідомо не лічить (клас: тести, знімки, шари поза коренем), — не збій: його відсікає фільтр
приладу до читання, і `непрочитано` там не кличуть. Самоперевірка приладу, що навмисно дає зламаний вхід, обгортає
його в `окремо()`, тест на штучному дереві кличе `скинути()` (`tearDownModule`): записане там до виходу не доходить.
"""
import ast
import atexit
import contextlib
import os
import sys

_НЕПРОЧИТАНЕ = []


def непрочитано(що, причина):
    """Записує частину обсягу (файл, модуль, тека записів), яку прилад не прочитав, і чому."""
    _НЕПРОЧИТАНЕ.append((str(що), str(причина).strip().splitlines()[0][:200] if str(причина).strip() else '—'))


def непрочитано_модуль(тека, модуль, причина):
    """Модуль `тека/модуль.py`, якого прилад не імпортував: запис, лише коли файл є (нема файлу — нема й обсягу;
    прилад, що має для такого дерева запасний шлях, ним і йде)."""
    if os.path.isfile(os.path.join(тека, модуль + '.py')):
        непрочитано(f'джерела/{модуль}.py' if os.path.basename(os.path.normpath(тека)) == 'джерела'
                    else os.path.join(тека, модуль + '.py'), причина)


def розібрати(текст, шлях, **аргументи):
    """`ast.parse(текст)`; нерозбірний (`SyntaxError`, `ValueError` — нульовий байт) — записує `шлях` і дає None."""
    try:
        return ast.parse(текст, **аргументи)
    except (SyntaxError, ValueError) as е:
        непрочитано(шлях, f'{type(е).__name__}: {е}')
        return None


def записане():
    """Копія записаного: [(що, причина)]."""
    return list(_НЕПРОЧИТАНЕ)


def скинути():
    """Прибирає записане й дає його: тест на штучному дереві (`tearDownModule`), де частини обсягу нема навмисно."""
    було = list(_НЕПРОЧИТАНЕ)
    del _НЕПРОЧИТАНЕ[:]
    return було


@contextlib.contextmanager
def окремо():
    """Самоперевірка зі зламаним входом: записане всередині блоку прибирається й до коду виходу не доходить.

    Дає список, у який після блоку покладено записане в ньому, — щоб самоперевірка могла звірити й сам запис.
    """
    було = len(_НЕПРОЧИТАНЕ)
    своє = []
    try:
        yield своє
    finally:
        своє.extend(_НЕПРОЧИТАНЕ[було:])
        del _НЕПРОЧИТАНЕ[було:]


def _на_виході():
    """Наприкінці процесу: є непрочитане — перелік у stderr і код 1 (після звичайного виводу приладу)."""
    if not _НЕПРОЧИТАНЕ:
        return
    різні = list(dict.fromkeys(_НЕПРОЧИТАНЕ))
    try:
        sys.stdout.flush()
    except (OSError, ValueError):
        pass
    рядки = [f'непрочитано: {що} — {чому}' for що, чому in різні]
    рядки.append(f'прилад не прочитав {len(різні)} частин обсягу — «місць» неповне, код 1 (Д10)')
    try:
        sys.stderr.write('\n'.join(рядки) + '\n')
        sys.stderr.flush()
    except (OSError, ValueError):
        pass
    os._exit(1)


atexit.register(_на_виході)


def розібрати_мовчки(текст):
    """`ast.parse(текст)` для рядка, що може виявитись не кодом: нерозбірний — None без запису; хто знає, що це мав
    бути код, сам кличе `непрочитано`."""
    try:
        return ast.parse(текст)
    except (SyntaxError, ValueError):
        return None
