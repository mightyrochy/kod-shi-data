# -*- coding: utf-8 -*-
"""Обсяг частини (а) розвідки «Приховані»: кожне твердження `аудит/ПРОДУКТ.md` одиницею і покриття переліку.

Наряд `аудит/наряди/Приховані-розвідка.md` (слово власника 31.10 14:26, 14:51): мірка частини (а) — правила продукту,
кожен пункт `аудит/ПРОДУКТ.md`. Пункт часто несе кілька правил, тож одиниця — речення пункту: прилад не судить, він
лічить знаменник з детермінованим ід, щоб перелік `аудит/корені/Приховані-перелік-а.md` мав вердикт на кожну одиницю,
а покриття рахував скрипт, а не сесія.

Одиниця:
  - речення пункту списку (`- …` з продовженням рядків) чи абзацу поза списком; межа речення — «. » перед великою
    літерою, «« чи «„»; рядок таблиці — одиниця цілим; заголовки — не одиниці;
  - ід — `а:<рядок>.<k>`: рядок початку пункту в `аудит/ПРОДУКТ.md` на дереві, де прилад запущено, і номер речення
    в пункті; зміна файлу зсуває ід — перелік звіряють на тому самому дереві;
  - вид: `правило` — розділи рішень (рядки до «Рекомендації Codex»); `рекомендація` — розділ рекомендацій Codex
    («Статус: рекомендації для розгляду» — не рішення); `вступ` — абзац до першого розділу (як читати файл).

Покриття: одиниця покрита, коли її ід стоїть першою клітинкою рядка таблиці переліку (`| а:12.1 | … |`); перевірена —
коли в тому самому рядку вердикт (друга клітинка) починається з `ДОТРИМАНО` чи `ВАДА` (решта — `ГІПОТЕЗА`,
`НЕ-КОДОМ`, `ВІДКЛАДЕНО`, `РЕКОМЕНДАЦІЯ`: вердикт без виміру коду).

Запуск з кореня репозиторію:
  python3 джерела/прилади/приховані_a_обсяг.py                         одиниці (ід ⇥ вид ⇥ розділ ⇥ текст)
  python3 джерела/прилади/приховані_a_обсяг.py --перелік аудит/корені/Приховані-перелік-а.md
      покриття за видом; непокриті ід — списком; останній рядок `непокрито: <N>`.
"""
import argparse
import os
import re
import sys

КОРІНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ПРОДУКТ = os.path.join(КОРІНЬ, "аудит", "ПРОДУКТ.md")
_МЕЖА = re.compile(r"(?<=[.!?])\s+(?=[А-ЯІЇЄҐA-Z«„])")
ПЕРЕВІРЕНО = ("ДОТРИМАНО", "ВАДА")


def _пункти(рядки):
    """(рядок початку, розділ, текст) кожного пункту списку, абзацу чи рядка таблиці."""
    розділ, пункти, поточний = "вступ", [], None
    for н, р in enumerate(рядки, 1):
        if р.startswith("#"):
            поточний = None
            розділ = "вступ" if р.startswith("# ") else р.lstrip("#").strip()
            continue
        if not р.strip():
            поточний = None
            continue
        if р.startswith("|"):
            поточний = None
            if re.match(r"^\|[-| ]+\|$", р.strip()) or (н < len(рядки) and рядки[н].startswith("|---")):
                continue
            пункти.append([н, розділ, р.strip()])
            continue
        if р.startswith("- ") or поточний is None:
            поточний = [н, розділ, р[2:].strip() if р.startswith("- ") else р.strip()]
            пункти.append(поточний)
        else:
            поточний[2] += " " + р.strip()
    return пункти


def одиниці(шлях=ПРОДУКТ):
    рядки = open(шлях, encoding="utf-8").read().split("\n")
    вихід, рекомендації = [], False
    for н, розділ, текст in _пункти(рядки):
        if розділ.startswith("Рекомендації Codex"):
            рекомендації = True
        вид = "вступ" if розділ == "вступ" else ("рекомендація" if рекомендації else "правило")
        речення = [текст] if текст.startswith("|") else [р for р in _МЕЖА.split(текст) if р.strip()]
        for k, р in enumerate(речення, 1):
            вихід.append(("а:%d.%d" % (н, k), вид, розділ, р.strip()))
    return вихід


def покриття(перелік):
    ід_вердикт = {}
    for р in open(перелік, encoding="utf-8"):
        м = re.match(r"^\|\s*(а:\d+\.\d+)\s*\|\s*([^|]*)\|", р)
        if м:
            ід_вердикт[м.group(1)] = м.group(2).strip()
    всі = одиниці()
    за_видом, непокриті = {}, []
    for ід, вид, _, _ in всі:
        с = за_видом.setdefault(вид, [0, 0, 0])
        с[0] += 1
        if ід in ід_вердикт:
            с[1] += 1
            if ід_вердикт[ід].startswith(ПЕРЕВІРЕНО):
                с[2] += 1
        else:
            непокриті.append(ід)
    for вид, (усього, покр, перев) in sorted(за_видом.items()):
        print("%s: одиниць %d, з вердиктом %d, перевірено виміром %d" % (вид, усього, покр, перев))
    зайві = sorted(set(ід_вердикт) - {о[0] for о in всі})
    if зайві:
        print("ід переліку поза ПРОДУКТ.md: " + ", ".join(зайві))
    if непокриті:
        print("непокриті: " + ", ".join(непокриті))
    print("непокрито: %d" % len(непокриті))


def main():
    п = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    п.add_argument("--перелік")
    а = п.parse_args()
    if а.перелік:
        покриття(а.перелік)
        return
    for о in одиниці():
        print("\t".join(о))


if __name__ == "__main__":
    sys.exit(main())
