# -*- coding: utf-8 -*-
"""Штучні дерева для приладу заміни: семантика виробників, межі обсягу й храповик.

Запуск: python джерела/прилади/тест_корінь_е3_заміна_з_перевіркою.py
Продукт, моделі, каталог і мережа не запускаються.
"""
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import textwrap
import unittest

import корінь_е3_заміна_з_перевіркою as ПРИЛАД
import обсяг_приладу as ОБСЯГ


class ПриладЗаміни(unittest.TestCase):
    """Перевіряє класи місць на незалежних від продукту маленьких програмах."""

    def setUp(self):
        """Створює ізольоване дерево всередині TEMP обгортки."""
        self.тимчасова = tempfile.TemporaryDirectory(prefix='заміна_тест_')
        self.корінь = Path(self.тимчасова.name)
        (self.корінь / 'джерела').mkdir()

    def tearDown(self):
        """Прибирає лише створене тестом дерево й очікувані помилки обсягу."""
        ОБСЯГ.скинути()
        self.тимчасова.cleanup()

    def записати(self, шлях, текст):
        """Кладе фікстуру з точно визначеним джерельним текстом."""
        файл = self.корінь / 'джерела' / шлях
        файл.parent.mkdir(parents=True, exist_ok=True)
        файл.write_text(textwrap.dedent(текст).lstrip(), encoding='utf-8')

    def місця(self):
        """Повертає лише позначених виробників; помилки читання перевіряються окремо."""
        return [к for к in ПРИЛАД.сканувати(self.корінь)[0] if к.умови]

    def test_ремонт_без_суду(self):
        """Текст і машинна заява одного ремонту — одне місце умови а."""
        self.записати('правило.py', '''
            def правило(образ):
                return зн(ремонт="замінити гольф на кремовий", ремонт_заяви=[м.заява("replace_top")])
        ''')
        self.assertEqual([(к.вид, к.умови) for к in self.місця()], [('ремонт', 'а')])

    def test_суд_початкового_образу_не_лікує_пораду(self):
        """Суд іншого складу не є судом образу з порадою."""
        self.записати('правило.py', '''
            def правило(образ):
                суд(образ)
                return зн(ремонт="додати шарф")
        ''')
        self.assertEqual(len(self.місця()), 1)

    def test_імпорт_і_вкладена_тека(self):
        """Прилад іде вглиб, розгортає імпортоване значення й локальну змінну."""
        self.записати('пакет/дані.py', 'ПОРАДА = "замінити верх на темніший"')
        self.записати('пакет/шлях.py', '''
            from пакет.дані import ПОРАДА as текст
            def правило():
                ремонт = текст
                return зн(ремонт=ремонт)
        ''')
        self.assertTrue(any(к.файл.endswith('пакет/шлях.py') for к in self.місця()))

    def test_форматування_не_розгортає_реєстр(self):
        """Параметри f-рядка є даними, а не ще тисячею текстів реєстру."""
        self.записати('правило.py', '''
            C = {"поріг": "неодягнені речі"}
            def правило(слот):
                return зн(ремонт=f"замінити {слот} на річ L*{C['поріг']}")
        ''')
        к = self.місця()[0]
        self.assertIn('{}', к.текст)
        self.assertNotIn('неодягнені', к.текст)

    def test_накопичення_ремонту(self):
        """Виробник через append теж досягає поля ремонту."""
        self.записати('правило.py', '''
            def правило():
                ремонт = []
                ремонт.append("замінити взуття")
                return зн(ремонт=ремонт)
        ''')
        self.assertTrue(any(к.вид == 'ремонт' for к in self.місця()))

    def test_опис_альтернативи_без_дієслова(self):
        """Іменний опис іншої речі — теж пропозиція."""
        self.записати('правило.py', 'def правило(): return зн(ремонт="важча пара того самого слота")')
        self.assertEqual(len(self.місця()), 1)

    def test_заява_без_тексту(self):
        """Машинний код ремонту не губиться за відсутності людського тексту."""
        self.записати('правило.py', 'def правило(): return зн(ремонт_заяви=[м.заява("remove_duplicate_accessory")])')
        self.assertEqual(len(self.місця()), 1)

    def test_вікно_каталогу(self):
        """Спільне вікно ремонту без кандидата й суду — місце."""
        self.записати('правило.py', 'def правило(): return зн(запит_у_каталог=dict(слот="верх", цільова_L=[40, 50]))')
        self.assertEqual(len(self.місця()), 1)

    def test_пояснення_вхід_і_носіння(self):
        """Вимір, підтверджений вибір і стан носіння не є заміною речі."""
        self.записати('правило.py', '''
            def правило():
                return [зн(ремонт="виміряти довжину пальта"),
                        зн(ремонт="свідомий вибір лишити; це пояснення"),
                        зн(ремонт="застебнути комір")]
        ''')
        self.assertEqual(self.місця(), [])

    def test_копія_поля_не_виробник(self):
        """Проєкція ремонту не множить місця початкового виробника."""
        self.записати('правило.py', '''
            def правило(): return зн(ремонт="замінити пальто")
            def копія(з): return dict(ремонт=з.get("ремонт"))
        ''')
        self.assertEqual(len(self.місця()), 1)

    def test_коментарі_докстрінги_коди(self):
        """Згадки в документації й машинні ідентифікатори не є пропозиціями."""
        self.записати('правило.py', '''
            """замінити пальто"""
            # додати шарф
            def ф():
                """прибрати річ"""
                return "replacement_not_one_item"
        ''')
        self.assertEqual(self.місця(), [])

    def test_не_довіряє_тексту_про_суд(self):
        """Самоопис перевіреності не замінює виконуваного контролю."""
        self.записати('шлях.py', '''
            def заміна(кандидат):
                """Суд, межі та вибір уже перевірені."""
                return dict(готово=True, річ=кандидат)
        ''')
        self.assertEqual(self.місця()[0].умови, 'абв')

    def безпечний_код(self, контроль=''):
        """Повертає фікстуру контракту з місцем для додаткового контролю."""
        return '''
def заміна(кандидат, новий_образ, межі, явний_вибір):
    вердикт = суд(новий_образ)
    if not вердикт['пройдено']:
        return None
''' + textwrap.indent(textwrap.dedent(контроль).strip(), '    ') + '''
    return dict(готово=True, річ=кандидат, вердикт=вердикт)
'''

    def test_кожна_умова_окремо(self):
        """Повний суд сам не доводить межі та явний вибір."""
        self.записати('шлях.py', self.безпечний_код())
        self.assertEqual(self.місця()[0].умови, 'бв')

    def test_повний_контракт(self):
        """Домінуючі відмови трьох умов знімають місце."""
        self.записати('шлях.py', self.безпечний_код('''
            if not у_межах(кандидат, межі):
                return None
            if not зберігає_вибір(кандидат, явний_вибір):
                return None
        '''))
        self.assertEqual(self.місця(), [])

    def test_суд_у_сусідній_гілці(self):
        """If іншої гілки не домінує над виходом."""
        self.записати('шлях.py', '''
            def заміна(кандидат, новий_образ, інша):
                if інша:
                    вердикт = суд(новий_образ)
                    if not вердикт['пройдено']:
                        return None
                return dict(готово=True, річ=кандидат)
        ''')
        self.assertIn('а', self.місця()[0].умови)

    def test_сума_не_є_повним_проходженням(self):
        """Зменшення суми не гарантує, що ремонт не переніс зауваження."""
        self.записати('шлях.py', '''
            def заміна(кандидат, новий_образ, старий):
                вердикт = суд(новий_образ)
                if вердикт['сума'] >= старий['сума']:
                    return None
                return dict(готово=True, річ=кандидат)
        ''')
        self.assertIn('а', self.місця()[0].умови)

    def test_схема_не_ремонт(self):
        """Опис типів полів не є вікном пошуку кандидата."""
        self.записати('схема.py', '''
            РЯДОК = dict(тип="рядок")
            БУДЬ_ЩО = dict(тип="будь_що")
            СХЕМА = {"ремонт": список(РЯДОК), "запит_у_каталог": БУДЬ_ЩО}
        ''')
        self.assertEqual(self.місця(), [])

    def test_альтернатива_після_запиту_входу(self):
        """Жодна гілка умовного ремонту не губиться за запитом входу іншої гілки."""
        self.записати('правило.py', '''
            def ф(невідомо):
                return зн(ремонт=["назвати тканину речі"] if невідомо else ["розмір більший або інший крій"])
        ''')
        self.assertEqual(len(self.місця()), 1)

    def test_інший_тип_без_назви_речі(self):
        """У полі ремонту «взяти тип» називає річ через її тип."""
        self.записати('правило.py', 'def ф(): return зн(ремонт="взяти тип своєї пори")')
        self.assertEqual(len(self.місця()), 1)

    def test_умовне_розгортання_словника(self):
        """Ремонт у **умовному словнику належить тій самій знахідці."""
        self.записати('правило.py', '''
            def ф(є):
                return dict(суть="замінити річ", **({} if є else {"ремонт": "замінити пальто"}))
        ''')
        self.assertEqual(len(self.місця()), 1)

    def test_перевірка_іншого_кандидата(self):
        """Перевірена інша річ не доводить межі запропонованої."""
        self.записати('шлях.py', self.безпечний_код('''
            if not у_межах(інша, межі):
                return None
            if not зберігає_вибір(інша, явний_вибір):
                return None
        '''))
        self.assertEqual(self.місця()[0].умови, 'бв')

    def test_код_ремонту_через_словник_мови(self):
        """Зміст коду читається у виробника, словник перекладу не множить місця."""
        self.записати('мова.py', '''
            ЗАЯВИ = {"shorter_pair": "take a different shoe pair"}
            def заява(код): return dict(code=код)
        ''')
        self.записати('правило.py', '''
            import мова as м
            def ф(): return зн(ремонт_заяви=[м.заява("shorter_pair")])
        ''')
        self.assertEqual(len(self.місця()), 1)

    def test_умова_і_тіньова_змінна_не_текст(self):
        """Умова гілки та однойменна змінна поза comprehension не забруднюють пораду."""
        self.записати('правило.py', '''
            def ф():
                м = "замінити пальто"
                умова = "додати шарф"
                return зн(ремонт=[м for м in ("виміряти довжину",)] if умова else "запитати колір")
        ''')
        self.assertEqual(self.місця(), [])

    def test_js_шаблони_regex_коментарі_підстановка(self):
        """Вкладені шаблони, regex із лапками й коментарі не ховають живий запис."""
        self.записати('глибше/екран.js', '''
            // картка.речі[0] = інша;
            const р = /["']/g;
            const назва = `${дані ? `слот ${річ}` : 'річ'}`;
            картка.речі[індекс] = локальна.речі[0];
        ''')
        self.assertEqual([к.вид for к in self.місця()], ['підстановка JS'])
        self.assertFalse(ОБСЯГ.записане())

    def test_js_текст_і_фальшива_підстановка_в_рядку(self):
        """Текст для жінки лічиться, запис усередині рядка не виконується."""
        self.записати('екран.js', '''
            кнопка.textContent = 'Замінити';
            порада.textContent = 'Замінити гольф на темний';
            const приклад = 'картка.речі[0] = інша';
        ''')
        self.assertEqual(len(self.місця()), 1)

    def test_html_видимий_текст_і_inline_js(self):
        """Розмітка, inline JS та коментарі розбираються окремо."""
        self.записати('екран.html', '''
            <!-- додати шарф -->
            <button>Замінити</button><p>Додати шарф до образу</p>
            <script>картка.речі[0] = нова;</script>
        ''')
        self.assertEqual(len(self.місця()), 2)

    def test_виключення_інструментів_на_всіх_глибинах(self):
        """Проби, стенди й тести не маскуються під код продукту."""
        for п in ('проби/приклад.py', 'прилади/приклад.py', 'глибше/тест_приклад.py', 'стенд_приклад.js'):
            self.записати(п, 'порада = "замінити річ"')
        self.assertEqual(self.місця(), [])

    def test_нерозбірний_python_не_зменшує_число_мовчки(self):
        """Нерозбірна частина обсягу реєструється, а CLI виходить 1."""
        self.записати('зламаний.py', 'def ф(:')
        середовище = dict(os.environ, PYTHONUTF8='1')
        пр = subprocess.run([sys.executable, str(Path(ПРИЛАД.__file__).resolve()), '--корінь', str(self.корінь)],
                            capture_output=True, encoding='utf-8', env=середовище)
        self.assertEqual(пр.returncode, 1)
        self.assertIn('зламаний.py', пр.stderr)

    def test_непрочитаний_js(self):
        """Зіпсована лексема JS не видається за відсутність місць."""
        self.записати('зламаний.js', "const а = 'замінити річ")
        self.місця()
        self.assertTrue(ОБСЯГ.записане())

    def test_стабільний_вивід_cli(self):
        """Останній рядок є договором храповика, без каталогу та npm."""
        self.записати('правило.py', 'def ф(): return dict(ремонт="додати шарф")')
        пр = subprocess.run([sys.executable, str(Path(ПРИЛАД.__file__).resolve()), '--корінь', str(self.корінь)],
                            capture_output=True, encoding='utf-8', env=dict(os.environ, PYTHONUTF8='1'))
        self.assertEqual(пр.returncode, 0, пр.stderr)
        self.assertEqual(пр.stdout.strip().splitlines()[-1], 'місць: 1')


if __name__ == '__main__':
    unittest.main()
