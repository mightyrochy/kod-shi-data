"""Пояснює невизнані межі поля, включно зі статичними кандидатами без потоку."""
from корінь_річ_запис_речі_ланцюг import вирази


def кандидати(аналіз, місця):
    """Зіставляє кандидата з файловим доказом або конкретною розірваною ланкою.

    Синтаксична пара «поле і регекс в одній функції» — лише кандидат:
    вона не доводить ані ролі запису, ані використання саме цього поля.
    """
    а = аналіз
    відкинуті = {}

    def додати(файл, рядок, пункт, причина, обрив, функція=None):
        """Зберігає одну відтворювану причину для невизнаної межі."""
        ключ = (файл, рядок, пункт)
        if ключ in місця:
            return
        запис = dict(файл=файл, рядок=рядок, пункт=пункт, чому=причина,
                     обрив=обрив, функція=функція)
        if ключ not in відкинуті or причина < відкинуті[ключ]["чому"]:
            відкинуті[ключ] = запис

    def розрив(джерела, файл, рядок):
        """Називає конкретну ланку, від якої файловий шлях не доведено."""
        for ід, область in sorted(джерела):
            о = а.об_за_id[ід]
            if а.ланцюги.якорі.get(ід):
                return {"місце": f"{файл}:{рядок}", "причина":
                        "Граф передачі цього об’єкта не з’єднує область читання з файловим якорем."}
            return {"місце": f"{о.файл}:{о.рядок}", "причина":
                    "Від створеного об’єкта не доведено перенесення до файла каталогу."}
        return {"місце": f"{файл}:{рядок}", "причина":
                "Отримувач поля не має абстрактного об’єкта: не розв’язано значення або виклик, що його передає."}

    for о, ключ, вал, файл, рядок in а.записи.values():
        джерела = {(о.id, а.області_подій.get((о.id, файл, рядок)))}
        доказ = а.ланцюги.шлях(о, next(iter(джерела))[1])
        if доказ:
            continue
        теги = {в[0] for в in вал if not hasattr(в, "пол")}
        for пункт in ([1] if "D" in теги else []) + ([2] if а.код_ключ(ключ) else []) + ([4] if "TP" in теги else []):
            додати(файл, рядок, пункт, "Поле не визнано полем запису без файлового ланцюга.",
                   розрив(джерела, файл, рядок))

    for місце, чому in sorted(а.читання3.items()):
        файл, _, рядок = місце.rpartition(":")
        джерела = а.ланцюги.читання.get(місце, ())
        додати(файл, int(рядок), 3, "Читач слів знайдений; файловий ланцюг поля не доведено: " + чому,
               розрив(джерела, файл, int(рядок)))

    for ф in а.функції:
        вираз = [в for оп in ф.stmts for е in (оп.val, *оп.ctrl) for в in вирази(е)]
        регекси = [в for в in вираз if в.k == "call" and в.a[0].k == "attr" and
                   в.a[0].v in ("search", "match", "fullmatch", "findall", "finditer", "sub", "subn", "test", "exec")]
        if not регекси:
            continue
        for в in регекси:
            аргументи = [е for арг in в.a[1:] for е in вирази(арг)]
            пряма_межа = any(е.k == "sub" or (е.k == "call" and е.a[0].k == "attr" and е.a[0].v in ("get", "pop")) for е in аргументи)
            if not пряма_межа:
                причина = "Скалярний читач: виклик регексу не є межею поля; місце п.3 належить вихідному читанню запису."
                додати(ф.file, в.line, 3, причина, {"місце": f"{ф.file}:{в.line}", "причина": причина}, ф.fid)
        читання = []
        for в in вираз:
            if в.k == "sub" and в.a[1].k == "str":
                читання.append((в.line, в.a[1].v))
            elif в.k == "call" and в.a[0].k == "attr" and в.a[0].v in ("get", "pop", "getOrDefault") and len(в.a) > 1 and в.a[1].k == "str":
                читання.append((в.line, в.a[1].v))
        for рядок, ключ in sorted(set(читання)):
            джерела = а.ланцюги.читання.get(f"{ф.file}:{рядок}", ())
            доказ = next((а.ланцюги.шлях(а.об_за_id[ід], область) for ід, область in sorted(джерела)
                          if а.ланцюги.шлях(а.об_за_id[ід], область)), None)
            if доказ:
                причина = ("Поле кодове; читання коду не є читанням слів." if а.код_ключ(ключ) else
                           "Для цього читання не встановлено потоку тексту в словесний шаблон; сама наявність регексу у функції його не доводить.")
                обрив = {"місце": f"{ф.file}:{рядок}", "причина": причина}
            else:
                причина = "Синтаксичний кандидат: поле й регекс у функції; роль запису не доведено."
                обрив = розрив(джерела, ф.file, рядок)
            додати(ф.file, рядок, 3, причина, обрив, ф.fid)
    return [відкинуті[ключ] for ключ in sorted(відкинуті)]


def скомпільований(s, е, ф, fn, ім, арги, av):
    """Зберігає роль шаблону re/regex, включно з псевдонімами імпорту."""
    if ім == "compile" and арги:
        база = fn.a[0] if fn.k == "attr" else None
        модуль = s.мф.get(ф.file)
        псевдонім = модуль.псевдоніми.get(база.v) if модуль and база and база.k == "name" else None
        прямий = база and база.k == "name" and (база.v in ("re", "regex") or псевдонім in (("mod", "re"), ("mod", "regex")))
        імпорт = база and база.k == "call" and база.a[0].k == "name" and база.a[0].v == "__import__" and any(
            в.k == "str" and в.v in ("re", "regex") for в in база.a[1:])
        if прямий or імпорт:
            о = s.новий(е, "rx", ф)
            о.шаблон_слів = s.слово_в_патерні(арги[0], av[0])
            return {о}
    return None


def регекс_виклик(аналіз, ф, fn):
    """Розв’язує імпорт re/regex та зберігає стабільні вузли для кешу виразів."""
    from корінь_річ_запис_речі_розбір import E
    а = аналіз
    if id(fn) in а.регекс_виклики:
        return а.регекс_виклики[id(fn)]
    ал = а.мф[ф.file].псевдоніми.get(fn.v) if fn.k == "name" else None
    ім = None
    if ал and ал[0] == "name" and ал[1] in ("re", "regex"):
        ім = ал[2]
    elif fn.k == "attr" and fn.a[0].k == "name" and а.мф[ф.file].псевдоніми.get(fn.a[0].v) in (("mod", "re"), ("mod", "regex")):
        ім = fn.v
    вихід = E("attr", ім, [E("name", "re", line=fn.line)], fn.line) if ім else fn
    а.регекс_виклики[id(fn)] = вихід
    return вихід


def модуль_виразу(аналіз, ф, вираз):
    """Розв’язує звичайний імпорт і прямий __import__ з літеральною назвою."""
    if вираз.k == "name":
        return аналіз.модуль_за_іменем(ф, вираз.v)
    if вираз.k == "call" and вираз.a[0].k == "name" and вираз.a[0].v == "__import__" and len(вираз.a) > 1 and вираз.a[1].k == "str":
        return аналіз.по_імені_модуля.get(вираз.a[1].v.split(".")[0])
    return None


def позиційний_ітератор(а, е, ф, ім, аргументи):
    """Зберігає позиції enumerate/zip та окремість числового індексу й запису."""
    ітератор = а.новий(е, "list", ф)
    пара = а.новий(е.a[0], "tuple", ф)
    значення = ([{("N", "індекс")}, а.елемент(аргументи[0])] if ім == "enumerate" and аргументи else
                [а.елемент(в) for в in аргументи])
    for і, вал in enumerate(значення):
        а.зберегти_в_об(пара, str(і), вал)
        а.зберегти_в_об(пара, "*", вал)
    а.зберегти_в_об(ітератор, "*", {пара})
    return {ітератор}


def змішане_читання(а, е, fn, ім, арги, av, kv, імена, rv, усі, ф, місце, власна):
    """Об’єднує результати get для кожного можливого типу отримувача.

    XML-вузол і запис можуть жити в одній змінній аналізу; жодна гілка
    не може відкинути другу через раннє повернення за any(тип).
    """
    if ім != "get" or fn.k != "attr":
        return None
    вузли = frozenset(в for в in rv if hasattr(в, "пол") and в.вид in ("page", "node", "feed"))
    інші = frozenset(rv) - вузли
    if not вузли or not any(hasattr(в, "пол") and в.вид in ("dict", "rec") for в in інші):
        return None
    return set(а.вбудований(е, fn, ім, арги, av, kv, імена, вузли, усі, ф, місце, власна)) | set(
        а.вбудований(е, fn, ім, арги, av, kv, імена, інші, усі, ф, місце, власна))


def позиційне_поле(а, вал, індекс, місце):
    """Читає відому позицію кортежу; невідомий ключ словника читає значення, не ключі."""
    вихід = set()
    for в in вал:
        ключ = None
        if hasattr(в, "пол") and в.вид in ("tuple", "list", "pairs") and індекс.k == "const" and isinstance(індекс.v, int):
            кандидат = str(int(індекс.v))
            if кандидат in в.пол:
                ключ = кандидат
        вихід.update(а.поле({в}, ключ, місце))
    return вихід
