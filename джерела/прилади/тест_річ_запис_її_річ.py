def рядок_файла(файл, вираз):
    """Номер (1-based) єдиного рядка `вираз` у поточному файлі продукту."""
    збіги = [і for і, р in enumerate((КОРІНЬ / файл).read_text(encoding='utf-8').splitlines(keepends=True), 1)
             if р == вираз]
    assert len(збіги) == 1, f'{файл}: очікувано 1 збіг рядка, знайдено {len(збіги)}'
    return збіги[0]


def лічба(правки=()):
    """Місця приладу окремим процесом — на дереві чи на копії `джерела/` з правками [(файл, старе, нове)]."""
    with tempfile.TemporaryDirectory() as тека:
        джерела = ДЖЕРЕЛА
        if правки:
            джерела = Path(тека) / 'джерела'
            shutil.copytree(ДЖЕРЕЛА, джерела, ignore=shutil.ignore_patterns(
                'прилади', 'проби', 'лабораторія', 'node_modules', '__pycache__', '.pytest_cache'))
            for файл, старе, нове in правки:
                шлях = джерела / Path(файл).relative_to('джерела')
                текст = шлях.read_text(encoding='utf-8')
                assert текст.count(старе) == 1, f'{файл}: мутант не стає — рядка нема чи він не один'
                шлях.write_text(текст.replace(старе, нове), encoding='utf-8')
        вих = запустити_python([sys.executable, '-X', 'utf8', '-W', 'ignore', str(Path(Я.__file__)), '--json',
                              f'--джерела={джерела}'], cwd=КОРІНЬ, capture_output=True, text=True, timeout=900)
    if вих.returncode:
        raise AssertionError(вих.stderr[-3000:])
    return json.loads(вих.stdout.strip().splitlines()[-1])


def записи(місця, файл):
    """{сцена/запис} входів, у яких прилад бачить місце у `файл`."""
    return {'/'.join(р['вхід'].split('/')[-3:])[:-len(Path(р['вхід']).name) + 8] for р in місця if р['файл'] == файл}


class Клас(unittest.TestCase):
    """Число на дереві й мутанти 14326: місце — поле, що залежить від уривка, хоч би й не рівне йому."""

    def мутант(self, нове):
        return лічба([(РІЧ, НАЗВА, НАЗВА.replace('назва = ', 'назва = ' + нове, 1))])

    def test_дерево(self):
        """ПІСЛЯ #3502 на дереві: назва з `name`, переклад окремо — місць 0 (до: `річ_з_фото.py` 2191, `мовний_шар.js` 614)."""
        м = лічба()
        self.assertEqual(м, [], м)

    def test_уривок(self):
        """Назва знову з `quote` перед `name` — те саме місце, ті самі чотири записи."""
        м = self.мутант(УРИВОК + ' or ')
        self.assertEqual({(р['файл'], р['рядок']) for р in м}, {(РІЧ, рядок_файла(РІЧ, НАЗВА))}, м)
        self.assertEqual(записи(м, РІЧ), УСІ)

    def test_дописок(self):
        """14326: `назва = quote + " ·"` — те саме місце, ті самі чотири записи (рівність давала 0)."""
        м = self.мутант('(' + УРИВОК + ' or "") + " ·" or ')
        self.assertEqual(записи(м, РІЧ), УСІ)

    def test_усічення(self):
        """14326: `quote.split(",")[0]` — чотири записи (рівність бачила один)."""
        м = self.мутант(УРИВОК + '.split(",")[0] or ')
        self.assertEqual(записи(м, РІЧ), УСІ)

    def test_без_займенника(self):
        """Уривок без першого слова («спідниці», «сукнею Амора…») — те саме місце."""
        м = self.мутант('" ".join(' + УРИВОК + '.split()[1:]) or ')
        self.assertEqual(записи(м, РІЧ), УСІ)

    def test_назва_з_назви(self):
        """Назва з `name`, уривок не читається (чинний код іншою формою): місця в `річ_з_фото.py` нема (чесний нуль)."""
        м = лічба([(РІЧ, НАЗВА, ('        назва = _ВМ.текст((р.get("name") or {}).get("value") if isinstance('
                                 'р.get("name"), dict) else р.get("name"))\n'))])
        self.assertEqual(записи(м, РІЧ), set(), м)

    def test_переклад_у_спільному_виклику(self):
        """Власна назва знову йде в один виклик перекладу з описом образу (як до #3502) — місце перекладу."""
        м = лічба([(ПЕРЕКЛАД, *СПІЛЬНА), (ПЕРЕКЛАД, *ОКРЕМА)])
        self.assertEqual({(р['файл'], р['рядок']) for р in м}, {(ПЕРЕКЛАД, рядок_файла(ПЕРЕКЛАД, ЗАПИС_ПЕРЕКЛАДУ))}, м)


