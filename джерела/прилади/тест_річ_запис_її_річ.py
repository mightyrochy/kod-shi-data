"""Перевіряє лічбу її речі на записі нічного прогону 07.11 і на тому самому записі без уривка."""
from pathlib import Path
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parent))
import річ_запис_її_річ as Я

КОРІНЬ = Path.cwd().resolve()
ЗАПИС = 'аудит/проби/Е1-нічний-живий-20261107/ж4_робота_спідниця_фото/VIDPOVIDI/seed3_01_мовний_шар_хід_розмови.txt'


def місця(корінь, шлях):
    """[(файл, поле, значення)] порушень одного запису — тим самим правилом, що й `лічити`."""
    sys.path.insert(0, str(КОРІНЬ / 'джерела'))
    import мовний_шар as М
    import річ_з_фото as РФ
    слід = Я.Трасування(КОРІНЬ / 'джерела')
    записи, ширші, поля = Я.прогнати(корінь, шлях, 'розмова', (М, РФ), слід)
    вих = []
    for запис in записи:
        for ключ, значення in Я.рядки(запис):
            if Я.н(значення) in ширші and Я.н(значення) not in поля:
                файл, _ = слід.місце(ключ, значення)
                вих.append((Path(файл).relative_to(КОРІНЬ).as_posix(), ключ, значення))
    return вих


class ЇїРіч(unittest.TestCase):
    """Незмінений код продукту на записаній відповіді шару."""

    def test_уривок_у_назві_її_речі(self):
        """«моєї спідниці» — уривок її речення — стає назвою її запису в річ_з_фото.py."""
        м = місця(КОРІНЬ, ЗАПИС)
        self.assertIn(('джерела/річ_з_фото.py', 'назва', 'моєї спідниці'), м)

    def test_без_уривка_місця_нема(self):
        """Та сама відповідь без уривка про спідницю: назва — з назви речі, місця нема."""
        текст = (КОРІНЬ / ЗАПИС).read_text(encoding='utf-8').replace('"quote": "моєї спідниці"', '"quote": ""')
        with tempfile.TemporaryDirectory() as тека:
            (Path(тека) / 'запис.txt').write_text(текст, encoding='utf-8')
            м = місця(Path(тека), 'запис.txt')
        self.assertFalse([р for р in м if р[2] == 'моєї спідниці'], м)


if __name__ == '__main__':
    unittest.main()
