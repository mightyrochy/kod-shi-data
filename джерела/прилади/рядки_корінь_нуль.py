# -*- coding: utf-8 -*-
"""СИГНАЛ «РЯДОК → КОРІНЬ → ПРИЛАД 0»: нові рядки дошки, чий корінь уже має прилад кореня 0 на цьому дереві.

ЧОМУ. Вади нічного прогону 07.11 дійшли до коренів через 11 год після злиття PR перевірки: корінь із приладом 0
не лишає живому симптому місця, а побачити його мав хтось із пам'яті (ЗНАХІДКА менеджера 08.11). Тут перевірка в мить
дії: щойно в `main` злито PR з рядками дошки, прилад називає ті з них, чий корінь не тримає жодного місця.
Це сигнал, а не гейт: код виходу завжди 0 (крім помилки запуску), CI він не валить.

ЩО РОБИТЬ. Нові рядки — додані рядки `| N | …` у `аудит/дошка/**/*.md` між `--база` і `--голова` (за замовчуванням
`HEAD^` і `HEAD`; push у `main` — `event.before`). Корінь рядка — слова після «корінь/кореня/коренем/корені…» (до `·`, `;`, `|`, `(`) і шлях `аудит/корені/<ім'я>.md`;
що збігаються з іменем паспорта `аудит/корені/<корінь>.md`. Для кожного кореня з рядком `прилад:` прилад запускається
в дереві `--репо` так само, як його кличе храповик кореня (`храповик_кореня.розібрати_паспорт`, `лічити`); `місць: 0` —
корінь у переліку. Читаються й повтори симптому `заміна | N | …` (головний випадок), крім рядків із статусом ЗАКРИТО. Інший корінь, паспорт без приладу чи рядок без кореня — у переліку не показується, лише число в
підсумку. Прилад із помилкою — рядок «прилад не дав числа» (не мовчки пропуск).

ЗАПУСК (з кореня репозиторію): python3 джерела/прилади/рядки_корінь_нуль.py [--база SHA] [--голова SHA] [--репо ТЕКА]
Вивід — stdout і `$GITHUB_STEP_SUMMARY`; перелік — ще й `::warning` (видно в анотаціях прогону). Канал — workflow
`.github/workflows/syhnal-ryadky.yml`.
"""
import argparse
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from храповик_кореня import ТЕКА_КОРЕНІВ, git, лічити, розібрати_паспорт

ДОШКА = 'аудит/дошка/'
# Новий рядок `| N | …` чи повтор симптому `заміна | N | …` (`заміна!`); «стан N:» симптому не несе й не читається.
РЯДОК = re.compile(r'^\+(заміна!?\s*)?\| *(\d+) *\|(.*)$')
# Корінь у тексті: слово «корін…/корен…» у будь-якому відмінку (корінь, кореня, кореню, коренем, корені, коренів)
# і ділянка до `·`, `;`, `|`, `(`; або шлях паспорта `аудит/корені/<ім'я>.md`.
КОРІНЬ = re.compile(r'кор(?:ін|ен)[а-яіїєь]*\s+([^·;|(]+)')
ШЛЯХ = re.compile(r'корені/([^\s`.,;|)]+)\.md')
ІМ_СИМВОЛИ = r'[\w-]'


def нові_рядки(репо, база, голова):
    """→ [(номер, текст)] доданих рядків дошки між базою й головою."""
    різниця = git(репо, 'diff', '--unified=0', '--no-color', база, голова, '--', ДОШКА)
    return [(int(м.group(2)), м.group(3), bool(м.group(1)))
            for р in різниця.splitlines() if (м := РЯДОК.match(р))]


def закритий(текст):
    """Рядок із клітинкою статусу (четвертою від №) «ЗАКРИТО …» — не симптом, що живе."""
    клітинки = re.split(r'(?<!\\)\|', '|' + текст)
    return len(клітинки) > 3 and клітинки[3].replace('*', '').strip().startswith('ЗАКРИТО')


def корені_рядка(текст, імена):
    """Імена паспортів, названі після «корінь/корені» в тексті рядка (повне ім'я, найдовше перемагає)."""
    знайдені = []
    for ім in ШЛЯХ.findall(текст):
        if ім in імена and ім not in знайдені:
            знайдені.append(ім)
    for ділянка in КОРІНЬ.findall(текст):
        for ім in sorted(імена, key=len, reverse=True):
            if re.search(rf'(?<!{ІМ_СИМВОЛИ}){re.escape(ім)}(?!{ІМ_СИМВОЛИ})', ділянка) and ім not in знайдені:
                знайдені.append(ім)
    return знайдені


def main():
    п = argparse.ArgumentParser()
    п.add_argument('--репо', default='.')
    п.add_argument('--база', default='HEAD^')
    п.add_argument('--голова', default='HEAD')
    а = п.parse_args()
    репо = os.path.abspath(а.репо)
    база = а.база if а.база.strip('0') else 'HEAD^'
    try:
        рядки = нові_рядки(репо, база, а.голова)
    except subprocess.CalledProcessError:
        try:  # база з події не отримана — перший батько голови
            рядки = нові_рядки(репо, а.голова + '^', а.голова)
        except subprocess.CalledProcessError as е:
            print(f'сигнал рядків: базу {база} не отримано ({е}); порожньо')
            return 0
    теки = os.path.join(репо, ТЕКА_КОРЕНІВ)
    імена = sorted(ф[:-3] for ф in os.listdir(теки) if ф.endswith('.md'))
    за_коренем = {}
    без_кореня = закриті = 0
    for номер, текст, заміна in рядки:
        if закритий(текст):
            закриті += 1
            continue
        ім = корені_рядка(текст, імена)
        if not ім:
            без_кореня += 1
        for к in ім:
            за_коренем.setdefault(к, []).append(f'{номер} (заміна)' if заміна else str(номер))
    вихід, нуль, інші, без_приладу, збої = [], [], [], [], []
    for к, номери in sorted(за_коренем.items()):
        with open(os.path.join(теки, к + '.md'), encoding='utf-8') as ф:
            прилад, арг, _, _ = розібрати_паспорт(ф.read())
        if not прилад:
            без_приладу.append(к)
            continue
        число, причина = лічити(репо, прилад, арг)
        if число is None:
            збої.append(f'{к}: прилад не дав числа ({причина})')
        elif число == 0:
            нуль.append((к, номери))
        else:
            інші.append((к, число))
    вихід.append(f'## Нові рядки дошки: {len(рядки)} (з них замін {sum(1 for _, _, з in рядки if з)}); закритих {закриті}; без названого кореня — {без_кореня}')
    if нуль:
        вихід.append('')
        вихід.append('| рядок | корінь | прилад |')
        вихід.append('|---|---|---|')
        for к, номери in нуль:
            for н in номери:
                вихід.append(f'| {н} | {к} | 0 |')
        вихід.append('')
        вихід.append(f'Живий симптом при приладі кореня 0 ({len(нуль)} коренів): прилад кореня не бачить цього місця.')
    else:
        вихід.append('Рядків із коренем при приладі 0 нема.')
    if інші:
        вихід.append('Корені з місцями (не сигнал): ' + ', '.join(f'{к} {ч}' for к, ч in інші))
    if без_приладу:
        вихід.append('Корені без приладу: ' + ', '.join(без_приладу))
    for з in збої:
        вихід.append(f'ПРИЛАД НЕ ДАВ ЧИСЛА — {з}')
    текст = '\n'.join(вихід)
    print(текст)
    if нуль:
        print('::warning title=рядок дошки при приладі кореня 0::' + '; '.join(
            f'{н} → {к} → 0' for к, ном in нуль for н in ном))
    шлях = os.environ.get('GITHUB_STEP_SUMMARY')
    if шлях:
        with open(шлях, 'a', encoding='utf-8') as ф:
            ф.write(текст + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
