"""Суд на точних записах живого: без моделі, мережі та нечіткого добору промптів.

Вхід — точні записані JSON-промпти й відповіді з одного SHA, у тимчасовій теці.
Картка першого ходу відновлюється з порожнього паспорта, як у цих шести сценах.
Розмітка опори — проти картки, а не проти всіх слів жінки: незаписаний wants
і поради про вже підібраний образ не стають фактами картки.
"""
import argparse
import contextlib
import io
import json
import re
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

_SHA = 'a8500d6623cb8a10aa5037e5f7adbf2902be30ea'
_РОЗМІТКА = {
    'ж1_робота': (('01_мовний_шар_хід_розмови', '0'),),
    'ж2_побачення_вечір': (('01_мовний_шар_хід_розмови', '10'), ('02_мовний_шар_репліка', '10'),
                           ('05_мовний_шар_репліка', '10')),
    'ж3_кафе_20': (('01_мовний_шар_хід_розмови', '10'), ('02_мовний_шар_репліка', '100'),
                   ('04_мовний_шар_репліка', '1')),
    'ж3_свято_др': (('01_мовний_шар_хід_розмови', '010'), ('03_мовний_шар_репліка', '00'),
                    ('06_мовний_шар_репліка', '1')),
    'ж3_театр_блакитні_нейтралі': (('01_мовний_шар_хід_розмови', '10'), ('02_мовний_шар_репліка', '10'),
                                 ('04_мовний_шар_репліка', '01')),
    'ж5_свято_др': (('01_мовний_шар_хід_розмови', '010'), ('02_мовний_шар_репліка', '01'),
                    ('05_мовний_шар_репліка', '1')),
}


def прочитати_записи(тека):
    """Прочитати незмінені VIDPOVIDI; у гілці зберігається лише ручна розмітка."""
    записи = []
    for сцена, файли in _РОЗМІТКА.items():
        for ім, опора in файли:
            шлях = Path(сцена) / 'VIDPOVIDI' / ('seed3_' + ім + '.txt')
            т = (тека / шлях).read_text(encoding='utf8')
            промпт, відповідь = т.split('\n\n── ВІДПОВІДЬ', 1)
            промпт = промпт.split('\n', 1)[1]
            вид = 'хід' if 'хід_розмови' in ім else 'репліка'
            вхід = json.loads(промпт if вид == 'хід' else промпт.split('РЕПЛІКА:\n')[1])
            записи.append(dict(сцена=сцена, вид=вид, вхід=вхід, відповідь=відповідь.split('──\n', 1)[1].strip(),
                               опора_речень=[с == '1' for с in опора],
                               джерело=_SHA + ':аудит/живі_2610-1-2/' + шлях.as_posix()))
    return записи


def виміряти(тека=None, код=None):
    """Відтворити суд кожного речення й вибір мовця на незмінних відповідях."""
    if тека is None:
        # Лише локальні git-об'єкти: історичні записи не потрапляють у гілку.
        архів = subprocess.check_output(['git', 'archive', '--format=zip', _SHA,
                                         'аудит/живі_2610-1-2'], cwd=Path(__file__).resolve().parents[2])
        with tempfile.TemporaryDirectory(prefix='суд-картки-') as тимчасова:
            with zipfile.ZipFile(io.BytesIO(архів)) as з:
                з.extractall(тимчасова)
            return виміряти(Path(тимчасова) / 'аудит/живі_2610-1-2', код)
    sys.path.insert(0, str(код or Path(__file__).resolve().parents[1]))
    import мовний_шар as м
    записи = прочитати_записи(тека)
    докази, сцени, хибні = [], [], set()
    л = dict(сцен=0, записів=len(записи), добрих_речень=0, хибних_відмов=0,
             чужих_речень=0, прийнято_чужих=0, хибних_сцен=0, повторних_обовʼязкових_питань=0)
    for з in записи:
        об = json.loads(re.sub(r'^```json\s*|\s*```$', '', з['відповідь']).strip())
        if з['вид'] == 'хід':
            пр = м.прийняти_розмову(з['відповідь'])
            with contextlib.redirect_stdout(io.StringIO()):
                р = м.паспорт_з_шару(пр['внутрішня'], {}, слова_ходу=[з['вхід']['her_new_message']],
                                     частини=пр['частини'])
            записано = р['записано']
            тексти = [п['says'] for п in об['text']]
            є_факт = any(з['опора_речень'])
            пряма = (р['мовець'] == 'turn' and bool(р['текст']) and not р.get('не_записано')
                     and not р.get('бракує_обовʼязкового') and пр['частини'].get('need', 'none') == 'none')
            хибна = є_факт and not пряма
            л['хибних_сцен'] += int(хибна)
            # Перевірка стану коду, не заява про прогін браузера або нову модель.
            л['повторних_обовʼязкових_питань'] += int('occasion' in р['обовʼязкове'])
            сцени.append(dict(сцена=з['сцена'], очікується_факт=є_факт, картка=записано,
                              текст=р['текст'], мовець=р['мовець'], пряма_відповідь=bool(пряма),
                              не_записано=р.get('не_записано'), обовʼязкове=р['обовʼязкове'], відкинуто=р['відкинуто']))
            л['сцен'] += 1
        else:
            записано = з['вхід'].get('recorded', {})
            тексти = [об['text']]
        речення = [с for т in тексти for с in м._РЕЧЕННЯ.split(т) if с.strip()]
        assert len(речення) == len(з['опора_речень']), з['джерело']
        for с, добре in zip(речення, з['опора_речень']):
            прийнято, чому = м.суд_підтвердження(с, записано)
            л['добрих_речень'] += int(добре)
            л['хибних_відмов'] += int(добре and not прийнято)
            л['чужих_речень'] += int(not добре)
            л['прийнято_чужих'] += int(not добре and bool(прийнято))
            if добре and not прийнято:
                хибні.add(з['сцена'])
            докази.append(dict(джерело=з['джерело'], речення=с, очікується=добре,
                               прийнято=bool(прийнято), відкинуто=чому))
    л['сцен_із_хибними_відмовами_речень'] = len(хибні)
    запис = dict(occasion=dict(label='Свято, вечірка',
                              quote='вечірка на день народження подруги, субота ввечері', source='her'))
    контроль = ('Це вечірка на день народження подруги в суботу о 21:00.',
                'Це вечірка на день народження подруги в ресторані у суботу ввечері.',
                'Це вечірка на день народження сестри в суботу ввечері.',
                'part_of_day: evening.',
                'Вечірка на день народження подруги, субота ввечері. Куди ти збираєшся?')
    контролі = [dict(текст=т, прийнято=bool(м.суд_репліки(т, dict(recorded=запис))[0])) for т in контроль]
    # Доданий факт після дослівного уривка не може сховатися за його збігом.
    додані = [dict(текст=т, прийнято=bool(м.суд_підтвердження(т, запис)[0])) for т in (
        'Вечірка на день народження подруги, субота ввечері у ресторані.',
        'Вечірка на день народження подруги, субота ввечері з сестрою.')]
    л['контролів'] = len(контролі)
    л['контролів_відкинуто'] = sum(not к['прийнято'] for к in контролі)
    л['доданих_фактів_відкинуто'] = sum(not к['прийнято'] for к in додані)
    мітка = dict(occasion=dict(label='Театр, концерт', quote='сьогодні театр, вечірня вистава', source='her'))
    л['часткова_мітка_відкинута'] = int(not м.суд_підтвердження('Сьогодні концерт.', мітка)[0])
    return dict(лічба=л, сцени=сцени, речення=докази, контролі=контролі, додані_факти=додані)


def main():
    """Надрукувати числа, за потреби зберегти повний розбір кожного речення."""
    а = argparse.ArgumentParser(description=__doc__)
    а.add_argument('--код', type=Path)
    а.add_argument('--записи', type=Path, help='тека живі_2610-1-2 з git archive; без неї — тимчасовий локальний архів')
    а.add_argument('--запис', type=Path)
    п = а.parse_args()
    р = виміряти(п.записи, п.код)
    if п.запис:
        п.запис.write_text(json.dumps(р, ensure_ascii=False, indent=1) + '\n', encoding='utf8')
    print(json.dumps(р['лічба'], ensure_ascii=False))


if __name__ == '__main__':
    main()
