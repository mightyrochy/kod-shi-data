import os
import shutil
import stat
import subprocess
import sys
import tempfile

ТУТ = os.path.dirname(os.path.abspath(__file__))
СКРИПТ = os.path.join(ТУТ, 'згорнути_паспорти.py')
ПАСПОРТ = 'аудит/корені/Тест-корінь.md'
ІСТОРІЯ = 'аудит/корені/історія/Тест-корінь.md'
ПОЧАТОК = ('# Корінь Тест-корінь: стенд\n\nПроблема. Текст.\n\n## Стан і що лишилось\n\n'
           'Що лишилось: крок 1 і крок 2.\nЧисло приладу: 10.\n\n## Крок 0\n\nЗроблено крок 0.\n')
ПРОВАЛИ = []
# Стенд змінюється окремим PR від згортання (наряд «Паспорт-шапка-й-історія», диспетчер 20.11):
# він знає обидва згортання. НОВЕ — є `поділити_паспорти.py`: записи кроків ідуть у файл історії, заміни — у шапку.
НОВЕ = os.path.isfile(os.path.join(ТУТ, 'поділити_паспорти.py'))


def git(тека, *а, ок=(0,)):
    р = subprocess.run(['git', '-c', 'core.quotepath=off', *а], cwd=тека, capture_output=True, text=True, encoding='utf-8',
                       check=False)
    if р.returncode not in ок:
        raise SystemExit(f'git {" ".join(а)}: {р.returncode}\n{р.stdout}\n{р.stderr}')
    return р


def писати(тека, шлях, текст):
    повний = os.path.join(тека, шлях)
    os.makedirs(os.path.dirname(повний), exist_ok=True)
    with open(повний, 'w', encoding='utf-8') as ф:
        ф.write(текст)


def читати(тека, шлях):
    with open(os.path.join(тека, шлях), encoding='utf-8') as ф:
        return ф.read()


def новий_репозиторій():
    тека = tempfile.mkdtemp(prefix='стенд_паспорта_')
    git(тека, 'init', '-q', '-b', 'main')
    git(тека, 'config', 'user.name', 'стенд')
    git(тека, 'config', 'user.email', 'стенд@локально')
    писати(тека, ПАСПОРТ, ПОЧАТОК)
    os.makedirs(os.path.join(тека, 'джерела/прилади'))
    shutil.copy(СКРИПТ, os.path.join(тека, 'джерела/прилади/згорнути_паспорти.py'))
    for допоміжний in ('поділити_паспорти.py',):
        if not os.path.isfile(os.path.join(ТУТ, допоміжний)):
            continue
        shutil.copy(os.path.join(ТУТ, допоміжний), os.path.join(тека, 'джерела/прилади', допоміжний))
    git(тека, 'add', '-A')
    git(тека, 'commit', '-qm', 'основа')
    return тека


def коміт(тека, гілка, файли, повідомлення):
    git(тека, 'checkout', '-q', '-b', гілка, 'main')
    for шлях, текст in файли.items():
        писати(тека, шлях, текст)
    git(тека, 'add', '-A')
    git(тека, 'commit', '-qm', повідомлення)
    git(тека, 'checkout', '-q', 'main')


def злити(тека, гілка):
    git(тека, 'merge', '-q', '--no-ff', '-m', f'Злиття {гілка}', гілка)


def конфлікт(тека, гілка):
    """`merge-tree --write-tree main <гілка>`: код 1 — конфлікт."""
    return git(тека, 'merge-tree', '--write-tree', 'main', гілка, ок=(0, 1)).returncode == 1


def згорнути(тека, *аргументи):
    р = запустити_python([sys.executable, '-X', 'utf8', '-I', 'джерела/прилади/згорнути_паспорти.py', *аргументи], cwd=тека,
                       capture_output=True, text=True, encoding='utf-8')
    return р.returncode, р.stdout, р.stderr


def мірило(назва, результат, очікувано, пояснення=''):
    так = результат == очікувано
    print(f'мірило: {назва} — {результат}{"" if так else f" (очікувано {очікувано}) {пояснення}"}')
    if not так:
        ПРОВАЛИ.append(назва)


def прибрати(тека):
    """Прибирає лише тимчасовий репозиторій стенда, включно з незаписуваними об'єктами Git у Windows."""
    шлях, тимчасова = os.path.realpath(тека), os.path.realpath(tempfile.gettempdir())
    if os.path.dirname(шлях) != тимчасова or not os.path.basename(шлях).startswith('стенд_паспорта_'):
        raise ValueError(f'не тимчасовий репозиторій стенда: {шлях}')

    def записуваний(дія, файл, помилка):
        """Повторює видалення після зняття атрибута лише читання; інші помилки не приховує."""
        if not isinstance(помилка[1], PermissionError):
            raise помилка[1]
        os.chmod(файл, stat.S_IWRITE)
        дія(файл)

    shutil.rmtree(шлях, onerror=записуваний)


# Запис кроку А і Б — один і той самий «зміст» у двох способах: прямо в паспорт (ДО) чи файлом гілки (ПІСЛЯ).
РОЗДІЛ_А, РОЗДІЛ_Б = '## Крок А — 15.11\n\nЗроблено крок А.', '## Крок Б — 15.11\n\nЗроблено крок Б.'


def паспорт_прямо(розділ, старе, нове):
    return ПОЧАТОК.replace(старе, нове) + '\n' + розділ + '\n'


def до():
    тека = новий_репозиторій()
    коміт(тека, 'а', {ПАСПОРТ: паспорт_прямо(РОЗДІЛ_А, 'крок 1 і крок 2', 'крок 2')}, 'крок А')
    коміт(тека, 'б', {ПАСПОРТ: паспорт_прямо(РОЗДІЛ_Б, 'Число приладу: 10', 'Число приладу: 7')}, 'крок Б')
    злити(тека, 'а')
    к = int(конфлікт(тека, 'б'))
    прибрати(тека)
    return к


ФАЙЛ_А = '<!-- крок А -->\n<<<< замінити\nЩо лишилось: крок 1 і крок 2.\n==== на\nЩо лишилось: крок 2.\n>>>>\n\n' + РОЗДІЛ_А + '\n'
ФАЙЛ_Б = '<!-- крок Б -->\n' + РОЗДІЛ_Б + '\n\n<<<< замінити\nЧисло приладу: 10.\n==== на\nЧисло приладу: 7.\n>>>>\n'
ДОДАТИ_А = 'аудит/корені/Тест-корінь.d/claude/а.md'
ДОДАТИ_Б = 'аудит/корені/Тест-корінь.d/claude/б.md'


def після():
    тека = новий_репозиторій()
    коміт(тека, 'а', {ДОДАТИ_А: ФАЙЛ_А}, 'крок А')
    коміт(тека, 'б', {ДОДАТИ_Б: ФАЙЛ_Б}, 'крок Б')
    # Порядок злиття — Б, потім А (назва «а» раніше за «б», тож порядок за назвою дав би протилежне).
    злити(тека, 'б')
    k = int(конфлікт(тека, 'а'))
    злити(тека, 'а')
    код, вивід, пом = згорнути(тека, '--лише-перевірити')
    мірило('перевірка голови без записів нічого не пише', (код, читати(тека, ПАСПОРТ) == ПОЧАТОК), (0, True))
    код, вивід, пом = згорнути(тека)
    текст = читати(тека, ПАСПОРТ)
    історія = читати(тека, ІСТОРІЯ) if НОВЕ else текст
    мірило('згортання двох файлів гілок', (код, 'згорнуто 2' in вивід), (0, True), вивід + пом)
    мірило('порядок записів в історії — порядок злиття',
           історія.find(РОЗДІЛ_Б) != -1 and історія.find(РОЗДІЛ_Б) < історія.find(РОЗДІЛ_А), True)
    if НОВЕ:
        мірило('записи кроків — в історії, не в шапці', (РОЗДІЛ_А in історія, РОЗДІЛ_Б in історія,
                                                        'Зроблено крок А' in текст, 'Зроблено крок Б' in текст),
               (True, True, False, False))
        мірило('шапка не росте від записів кроків',
               (текст.count('\n'), історія.startswith('# Історія кореня Тест-корінь')),
               (ПОЧАТОК.count('\n'), True))
    мірило('заміни застосовано в шапці', ('Що лишилось: крок 2.' in текст, 'Число приладу: 7.' in текст,
                                          'крок 1 і крок 2' in текст, 'Число приладу: 10' in текст),
           (True, True, False, False))
    мірило('файли й тека гілок видалено', os.path.exists(os.path.join(тека, 'аудит/корені/Тест-корінь.d')), False)
    git(тека, 'add', '-A')
    git(тека, 'commit', '-qm', 'згорнуто')
    код, вивід, пом = згорнути(тека)
    мірило('повторне згортання без змін', (код, 'файлів 0' in вивід, git(тека, 'status', '--porcelain').stdout), (0, True, ''))
    прибрати(тека)
    return k


def помилки_й_повтор():
    тека = новий_репозиторій()
    # дубль запису, що вже в паспорті; файл з невідомим коренем; не .md; незакрита заміна; нема старого тексту
    писати(тека, 'аудит/корені/Тест-корінь.d/claude/ок.md', '## Новий\n\nТекст.\n')
    писати(тека, 'аудит/корені/Тест-корінь.d/claude/дубль.md', '## Крок 0\n\nЗроблено крок 0.\n')
    писати(тека, 'аудит/корені/Нема-кореня.d/claude/х.md', '## Х\n\nТекст.\n')
    писати(тека, 'аудит/корені/Тест-корінь.d/claude/дані.json', '{}\n')
    писати(тека, 'аудит/корені/Тест-корінь.d/claude/незакрита.md', '<<<< замінити\nЧисло приладу: 10.\n==== на\nХ\n')
    писати(тека, 'аудит/корені/Тест-корінь.d/claude/нема.md', '<<<< замінити\nнема такого\n==== на\nХ\n>>>>\n')
    писати(тека, 'аудит/корені/Тест-корінь.d/claude/порожній.md', '<!-- нічого -->\n')
    код, вивід, пом = згорнути(тека, '--лише-перевірити')
    мірило('перевірка PR: код 1 і назви п’яти файлів', (код, [н for н in
           ('Нема-кореня.d/claude/х.md', 'дані.json', 'незакрита.md', 'нема.md', 'порожній.md') if н in пом]),
           (1, ['Нема-кореня.d/claude/х.md', 'дані.json', 'незакрита.md', 'нема.md', 'порожній.md']), пом)
    мірило('перевірка PR нічого не пише', читати(тека, ПАСПОРТ) == ПОЧАТОК, True)
    код, вивід, пом = згорнути(тека)
    текст = читати(тека, ПАСПОРТ)
    історія = читати(тека, ІСТОРІЯ) if НОВЕ else ''
    мірило('справний файл згорнуто (в історію чи паспорт), дубль не подвоєно',
           (код, текст.count('## Крок 0'), '## Новий' in історія, '## Новий' in текст, 'вже було 1' in вивід),
           (1, 1, НОВЕ, not НОВЕ, True), вивід + пом)
    мірило('файли з помилкою лишились, справний видалено',
           (os.path.exists(os.path.join(тека, 'аудит/корені/Тест-корінь.d/claude/ок.md')),
            os.path.exists(os.path.join(тека, 'аудит/корені/Тест-корінь.d/claude/дубль.md')),
            os.path.exists(os.path.join(тека, 'аудит/корені/Тест-корінь.d/claude/нема.md')),
            os.path.exists(os.path.join(тека, 'аудит/корені/Нема-кореня.d/claude/х.md'))), (False, False, True, True))
    прибрати(тека)


СТАРИЙ = ('# Корінь Поділ-корінь: стенд поділу\n\n## Проблема\n\nТекст проблеми.\n\n## Стан і що лишилось\n\n'
          'Що лишилось: крок 1 і крок 2.\n\nприлад: джерела/x.py\nбаза: джерела/x.py\n\n'
          '## Крок 1 — 05.11 (UTC)\n\nЗроблено крок 1.\n\nприлад-ні: не рядок приладу\n\n'
          '## Що лишилось\n\nУ середині історії: це шапка.\n\n## Рішення менеджера 19.11 — нове\n\nЧинне рішення.\n\n'
          '### Підкрок 20.11\n\nПідблок нового рішення — теж шапка.\n\n## Рішення менеджера 06.11 — старе\n\n'
          'Старе рішення — історія.\n')


def поділ_і_історія():
    """Поділ паспорта скриптом і звірка; далі крок: запис — в історію, шапка не росте, «що лишилось» — у шапку."""
    тека = новий_репозиторій()
    шлях = 'аудит/корені/Поділ-корінь.md'
    писати(тека, шлях, СТАРИЙ)
    git(тека, 'add', '-A')
    git(тека, 'commit', '-qm', 'старий паспорт')
    р = subprocess.run([sys.executable, '-X', 'utf8', '-I', 'джерела/прилади/поділити_паспорти.py'], cwd=тека,
                       capture_output=True, text=True, encoding='utf-8', check=False)
    шапка0, історія0 = читати(тека, шлях), читати(тека, 'аудит/корені/історія/Поділ-корінь.md')
    мірило('поділ: код і шапка без датованого кроку',
           (р.returncode, 'Зроблено крок 1' in шапка0, 'Зроблено крок 1' in історія0), (0, False, True), р.stdout + р.stderr)
    мірило('поділ: «Що лишилось» посеред історії, нове рішення з підблоком — в шапці',
           ('У середині історії' in шапка0, 'Підблок нового рішення' in шапка0, 
            'Старе рішення' in історія0), (True, True, True))
    з = subprocess.run([sys.executable, '-X', 'utf8', '-I', 'джерела/прилади/поділити_паспорти.py', '--звірити',
                        '--база', 'main'], cwd=тека, capture_output=True, text=True, encoding='utf-8', check=False)
    мірило('звірка: кожен рядок старого — в шапці чи історії, у порядку старого', з.returncode, 0, з.stdout + з.stderr)
    # крок: запис і заміна «Що лишилось» шапки
    писати(тека, 'аудит/корені/Поділ-корінь.d/claude/к.md',
           '<!-- крок -->\n## Крок 2 — 21.11\n\nЗроблено крок 2.\n\n<<<< замінити\nЩо лишилось: крок 1 і крок 2.\n'
           '==== на\nЩо лишилось: крок 2.\n>>>>\n')
    код, вивід, пом = згорнути(тека)
    шапка1, історія1 = читати(тека, шлях), читати(тека, 'аудит/корені/історія/Поділ-корінь.md')
    мірило('крок: запис — в історію, шапка не росте, «що лишилось» дійшло до шапки',
           (код, '## Крок 2' in історія1, '## Крок 2' in шапка1, шапка1.count('\n') == шапка0.count('\n'),
            'Що лишилось: крок 2.' in шапка1), (0, True, False, True, True), вивід + пом)
    прибрати(тека)


if __name__ == '__main__':
    д = до()
    п = після()
    мірило('ДО: конфліктів другої гілки після злиття першої (запис прямо в паспорт)', д, 1)
    мірило('ПІСЛЯ: конфліктів другої гілки (запис файлом гілки)', п, 0)
    помилки_й_повтор()
    if НОВЕ:
        поділ_і_історія()
    print(f'мірило: конфліктів ДО {д} з 1 → ПІСЛЯ {п} з 1; порушень стенда {len(ПРОВАЛИ)}')
    sys.exit(1 if ПРОВАЛИ else 0)
