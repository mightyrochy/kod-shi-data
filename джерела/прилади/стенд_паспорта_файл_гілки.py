# -*- coding: utf-8 -*-
"""СТЕНД ПАСПОРТА-ФАЙЛУ-ГІЛКИ: мірило ДО → ПІСЛЯ наряду «Паспорт-файл-гілки» (менеджер 15.11) на справжньому
`згорнути_паспорти.py` у тимчасових репозиторіях git (не `аудит/корені/` цього).

ДО. Дві гілки від одного `main`, кожна дописує крок того самого кореня прямо в паспорт (новий розділ у кінці й заміна
свого рядка «Що лишилось» / числа): після злиття першої друга зливається з конфліктом — `git merge-tree --write-tree`,
код 1 (конфліктів 1 з 1).
ПІСЛЯ. Ті самі кроки — файлами гілок `аудит/корені/<корінь>.d/<гілка>.md`: друга зливається без конфлікту (0 з 1);
після згортання обидва записи — у паспорті в ПОРЯДКУ ЗЛИТТЯ (зливаємо гілку з пізнішою назвою першою), заміни застосовані,
файли й теки гілок видалено, повторний запуск нічого не міняє.
Далі — що не мовчить: файл гілки без паспорта, з невідомим коренем, не `.md`, із незакритою заміною, із відсутнім
старим текстом, із рядком `прилад:` — код 1 з назвою файла, решта файлів згортається, цей лишається; `--лише-перевірити`
нічого не пише; запис, що вже стоїть у паспорті, — «вже було».

ЗАПУСК: python3 джерела/прилади/стенд_паспорта_файл_гілки.py   (друкує «мірило: …»; код 1 — хоч одне не те)
"""
import os
import shutil
import subprocess
import sys
import tempfile

ТУТ = os.path.dirname(os.path.abspath(__file__))
СКРИПТ = os.path.join(ТУТ, 'згорнути_паспорти.py')
ПАСПОРТ = 'аудит/корені/Тест-корінь.md'
ПОЧАТОК = ('# Корінь Тест-корінь: стенд\n\nПроблема. Текст.\n\n## Стан і що лишилось\n\n'
           'Що лишилось: крок 1 і крок 2.\nЧисло приладу: 10.\n\n## Крок 0\n\nЗроблено крок 0.\n')
ПРОВАЛИ = []


def git(тека, *а, ок=(0,)):
    р = subprocess.run(['git', '-c', 'core.quotepath=off', *а], cwd=тека, capture_output=True, text=True)
    if р.returncode not in ок:
        raise SystemExit(f'git {" ".join(а)}: {р.returncode}\n{р.stdout}\n{р.stderr}')
    return р


def писати(тека, шлях, текст):
    повний = os.path.join(тека, шлях)
    os.makedirs(os.path.dirname(повний), exist_ok=True)
    with open(повний, 'w', encoding='utf-8') as ф:
        ф.write(текст)


def читати(тека, шлях):
    with open(os.path.join(тека, шлях), encoding='utf-8') as ф:
        return ф.read()


def новий_репозиторій():
    тека = tempfile.mkdtemp(prefix='стенд_паспорта_')
    git(тека, 'init', '-q', '-b', 'main')
    git(тека, 'config', 'user.name', 'стенд')
    git(тека, 'config', 'user.email', 'стенд@локально')
    писати(тека, ПАСПОРТ, ПОЧАТОК)
    os.makedirs(os.path.join(тека, 'джерела/прилади'))
    shutil.copy(СКРИПТ, os.path.join(тека, 'джерела/прилади/згорнути_паспорти.py'))
    git(тека, 'add', '-A')
    git(тека, 'commit', '-qm', 'основа')
    return тека


def коміт(тека, гілка, файли, повідомлення):
    git(тека, 'checkout', '-q', '-b', гілка, 'main')
    for шлях, текст in файли.items():
        писати(тека, шлях, текст)
    git(тека, 'add', '-A')
    git(тека, 'commit', '-qm', повідомлення)
    git(тека, 'checkout', '-q', 'main')


def злити(тека, гілка):
    git(тека, 'merge', '-q', '--no-ff', '-m', f'Злиття {гілка}', гілка)


def конфлікт(тека, гілка):
    """`merge-tree --write-tree main <гілка>`: код 1 — конфлікт."""
    return git(тека, 'merge-tree', '--write-tree', 'main', гілка, ок=(0, 1)).returncode == 1


def згорнути(тека, *аргументи):
    р = subprocess.run([sys.executable, '-I', 'джерела/прилади/згорнути_паспорти.py', *аргументи], cwd=тека,
                       capture_output=True, text=True)
    return р.returncode, р.stdout, р.stderr


def мірило(назва, результат, очікувано, пояснення=''):
    так = результат == очікувано
    print(f'мірило: {назва} — {результат}{"" if так else f" (очікувано {очікувано}) {пояснення}"}')
    if not так:
        ПРОВАЛИ.append(назва)


# Запис кроку А і Б — один і той самий «зміст» у двох способах: прямо в паспорт (ДО) чи файлом гілки (ПІСЛЯ).
РОЗДІЛ_А, РОЗДІЛ_Б = '## Крок А — 15.11\n\nЗроблено крок А.', '## Крок Б — 15.11\n\nЗроблено крок Б.'


def паспорт_прямо(розділ, старе, нове):
    return ПОЧАТОК.replace(старе, нове) + '\n' + розділ + '\n'


def до():
    тека = новий_репозиторій()
    коміт(тека, 'а', {ПАСПОРТ: паспорт_прямо(РОЗДІЛ_А, 'крок 1 і крок 2', 'крок 2')}, 'крок А')
    коміт(тека, 'б', {ПАСПОРТ: паспорт_прямо(РОЗДІЛ_Б, 'Число приладу: 10', 'Число приладу: 7')}, 'крок Б')
    злити(тека, 'а')
    к = int(конфлікт(тека, 'б'))
    shutil.rmtree(тека)
    return к


ФАЙЛ_А = '<!-- крок А -->\n<<<< замінити\nЩо лишилось: крок 1 і крок 2.\n==== на\nЩо лишилось: крок 2.\n>>>>\n\n' + РОЗДІЛ_А + '\n'
ФАЙЛ_Б = '<!-- крок Б -->\n' + РОЗДІЛ_Б + '\n\n<<<< замінити\nЧисло приладу: 10.\n==== на\nЧисло приладу: 7.\n>>>>\n'
ДОДАТИ_А = 'аудит/корені/Тест-корінь.d/claude/а.md'
ДОДАТИ_Б = 'аудит/корені/Тест-корінь.d/claude/б.md'


def після():
    тека = новий_репозиторій()
    коміт(тека, 'а', {ДОДАТИ_А: ФАЙЛ_А}, 'крок А')
    коміт(тека, 'б', {ДОДАТИ_Б: ФАЙЛ_Б}, 'крок Б')
    # Порядок злиття — Б, потім А (назва «а» раніше за «б», тож порядок за назвою дав би протилежне).
    злити(тека, 'б')
    k = int(конфлікт(тека, 'а'))
    злити(тека, 'а')
    код, вивід, пом = згорнути(тека, '--лише-перевірити')
    мірило('перевірка голови без записів нічого не пише', (код, читати(тека, ПАСПОРТ) == ПОЧАТОК), (0, True))
    код, вивід, пом = згорнути(тека)
    текст = читати(тека, ПАСПОРТ)
    мірило('згортання двох файлів гілок', (код, 'згорнуто 2' in вивід), (0, True), вивід + пом)
    мірило('порядок записів — порядок злиття',
           текст.find(РОЗДІЛ_Б) != -1 and текст.find(РОЗДІЛ_Б) < текст.find(РОЗДІЛ_А), True)
    мірило('заміни застосовано', ('Що лишилось: крок 2.' in текст, 'Число приладу: 7.' in текст,
                                  'крок 1 і крок 2' in текст, 'Число приладу: 10' in текст),
           (True, True, False, False))
    мірило('файли й тека гілок видалено', os.path.exists(os.path.join(тека, 'аудит/корені/Тест-корінь.d')), False)
    git(тека, 'add', '-A')
    git(тека, 'commit', '-qm', 'згорнуто')
    код, вивід, пом = згорнути(тека)
    мірило('повторне згортання без змін', (код, 'файлів 0' in вивід, git(тека, 'status', '--porcelain').stdout), (0, True, ''))
    shutil.rmtree(тека)
    return k


def помилки_й_повтор():
    тека = новий_репозиторій()
    # дубль запису, що вже в паспорті; файл з невідомим коренем; не .md; незакрита заміна; нема старого тексту; прилад
    писати(тека, 'аудит/корені/Тест-корінь.d/claude/ок.md', '## Новий\n\nТекст.\n')
    писати(тека, 'аудит/корені/Тест-корінь.d/claude/дубль.md', '## Крок 0\n\nЗроблено крок 0.\n')
    писати(тека, 'аудит/корені/Нема-кореня.d/claude/х.md', '## Х\n\nТекст.\n')
    писати(тека, 'аудит/корені/Тест-корінь.d/claude/дані.json', '{}\n')
    писати(тека, 'аудит/корені/Тест-корінь.d/claude/незакрита.md', '<<<< замінити\nЧисло приладу: 10.\n==== на\nХ\n')
    писати(тека, 'аудит/корені/Тест-корінь.d/claude/нема.md', '<<<< замінити\nнема такого\n==== на\nХ\n>>>>\n')
    писати(тека, 'аудит/корені/Тест-корінь.d/claude/прилад.md', '## П\n\nприлад: джерела/x.py\n')
    писати(тека, 'аудит/корені/Тест-корінь.d/claude/порожній.md', '<!-- нічого -->\n')
    код, вивід, пом = згорнути(тека, '--лише-перевірити')
    мірило('перевірка PR: код 1 і назви шести файлів', (код, [н for н in
           ('Нема-кореня.d/claude/х.md', 'дані.json', 'незакрита.md', 'нема.md', 'прилад.md', 'порожній.md') if н in пом]),
           (1, ['Нема-кореня.d/claude/х.md', 'дані.json', 'незакрита.md', 'нема.md', 'прилад.md', 'порожній.md']), пом)
    мірило('перевірка PR нічого не пише', читати(тека, ПАСПОРТ) == ПОЧАТОК, True)
    код, вивід, пом = згорнути(тека)
    текст = читати(тека, ПАСПОРТ)
    мірило('справний файл згорнуто, дубль не подвоєно', (код, текст.count('## Крок 0'), 'Текст.' in текст, 'вже було 1' in вивід),
           (1, 1, True, True), вивід + пом)
    мірило('файли з помилкою лишились, справний видалено',
           (os.path.exists(os.path.join(тека, 'аудит/корені/Тест-корінь.d/claude/ок.md')),
            os.path.exists(os.path.join(тека, 'аудит/корені/Тест-корінь.d/claude/дубль.md')),
            os.path.exists(os.path.join(тека, 'аудит/корені/Тест-корінь.d/claude/нема.md')),
            os.path.exists(os.path.join(тека, 'аудит/корені/Нема-кореня.d/claude/х.md'))), (False, False, True, True))
    shutil.rmtree(тека)


if __name__ == '__main__':
    д = до()
    п = після()
    мірило('ДО: конфліктів другої гілки після злиття першої (запис прямо в паспорт)', д, 1)
    мірило('ПІСЛЯ: конфліктів другої гілки (запис файлом гілки)', п, 0)
    помилки_й_повтор()
    print(f'мірило: конфліктів ДО {д} з 1 → ПІСЛЯ {п} з 1; порушень стенда {len(ПРОВАЛИ)}')
    sys.exit(1 if ПРОВАЛИ else 0)
