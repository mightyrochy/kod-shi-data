# -*- coding: utf-8 -*-
"""Зібрати `джерела/назви_карток.json.gz` — {url картки: назва картки} із сирих жнив.

НАВІЩО (рядок 144 дошки). Назва у фіді часом не назва: бренд («Max Mara»),
рубрика («СУКНІ»), речення опису («Носи з класичними штанами…») або чужа мова.
Справжню назву крамниця пише на САМІЙ КАРТЦІ, і жнива її вже зняли — поле
`картка.назва` в `сирі/<магазин>.jsonl.gz` гілки `zhnyva-data`. Цей файл переносить
її в репозиторій, щоб `назва_речі.назва_для_показу` мала що читати на телефоні.

ЧОМУ ПРИЛАД, А НЕ МОДУЛЬ: сирі жнива в `main` не лежать (вони у своїй гілці й
важать десятки мегабайт), тож зібрати можна лише там, де вони розпаковані;
продукту потрібен РЕЗУЛЬТАТ, а не збирач. Тека `прилади/` саме для цього —
сканери складу (`склад`, `досяжність`, `gate_reach`, `audit_contracts`) її не
читають.

ЩО ПОТРАПЛЯЄ У ФАЙЛ. Лише ті url, які може спитати показ: url речі з каталогу
та його МОВНА СЕСТРА (`назва_речі.сторінки_речі` — той самий список, без нього
файл ріс би вчетверо, а читали б із нього чверть). Вимір 23.09.2026 на
`каталог_повний` + 47 файлів сирих жнив: 10 753 записи, 1.4 МБ json, 184 КБ .gz.

ПРОГІН:  cd джерела && python3 прилади/назви_карток_зібрати.py <тека з сирі/*.jsonl.gz>
"""
import gzip, json, os, sys
import xml.etree.ElementTree as ET

_тут = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _тут)
os.chdir(_тут)
import feed
import назва_речі as НР


def назви_із_жнив(тека):
    """{url: назва} з усіх `*.jsonl.gz` теки сирих жнив."""
    зібрано = {}
    for імя in sorted(os.listdir(тека)):
        if not імя.endswith(".jsonl.gz"):
            continue
        with gzip.open(os.path.join(тека, імя), "rt", encoding="utf-8") as f:
            for рядок in f:
                запис = json.loads(рядок)
                url = str(запис.get("url") or "").strip()
                назва = str((запис.get("картка") or {}).get("назва") or "").strip()
                if url and назва:
                    зібрано[url] = назва
    return зібрано


def потрібні(усі, шлях_каталогу):
    """Лише ті url, які показ справді спитає: url речі та її мовна сестра."""
    вибрані = {}
    for offer in ET.parse(шлях_каталогу).getroot().iter("offer"):
        for url in НР.сторінки_речі((offer.findtext("url") or "").strip()):
            if url in усі:
                вибрані[url] = усі[url]
    return вибрані


if __name__ == "__main__":
    тека_жнив = sys.argv[1] if len(sys.argv) > 1 else "../zhnyvarka/сирі"
    усі = назви_із_жнив(тека_жнив)
    вибрані = потрібні(усі, feed.каталог_на_диску())
    сирі = json.dumps(вибрані, ensure_ascii=False, sort_keys=True, indent=0).encode("utf-8")
    шлях = os.path.join(_тут, НР.НАЗВИ_КАРТОК_ІМ + ".gz")
    with gzip.open(шлях, "wb", compresslevel=9) as f:
        f.write(сирі)
    print("ФАКТ · карток у жнивах %d · потрібних каталогу %d · %s %d КБ"
          % (len(усі), len(вибрані), os.path.basename(шлях), os.path.getsize(шлях) // 1024))
