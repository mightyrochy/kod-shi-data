# -*- coding: utf-8 -*-
"""Лічба 2.11: скільки розходжень між переліками кольору та їхніми читачами (К-2, Р20).
Читачі: лексикон і сім'ї слів `verify`, назви кодів `внутрішня_мова`, схеми продукту, каталогу й пілота 5190,
латинські слова крамниць і синоніми розбору. Еталон — продукт (`внутрішня_мова.color_name`); код понад нього
дозволений, лише коли його оголошено в `словник_кольору` (пілотний). Працює й на гілці без словника — це «ДО».
Запуск: cd джерела && python3 -W ignore прилади/лічба_словника_кольору.py"""
import json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
import verify as V, внутрішня_мова as M, каталог_розбір as КР
try:
    import словник_кольору as СК
except ImportError:
    СК = None
продукт = dict(M.ТАБЛИЦЯ["color_name"]); коди, слова = set(продукт), set(продукт.values())
пілотні = set(СК.ПІЛОТНІ_КОДИ) if СК else set()
розходження = []


def звірити(читач, маємо, еталон, дозволені=frozenset()):
    for к in sorted(set(маємо) - set(еталон) - set(дозволені)):
        розходження.append("%s: зайве %s" % (читач, к))
    for к in sorted(set(еталон) - set(маємо)):
        розходження.append("%s: бракує %s" % (читач, к))


def переліки(вузол, шлях=""):
    if isinstance(вузол, dict):
        if isinstance(вузол.get("enum"), list) and "powder_pink" in вузол["enum"]:
            yield шлях, вузол["enum"]
        for к, в in вузол.items():
            yield from переліки(в, шлях + "/" + к)
    elif isinstance(вузол, list):
        for і, в in enumerate(вузол):
            yield from переліки(в, шлях + "/%d" % і)


звірити("verify.ЛЕКСИКОН", V.ЛЕКСИКОН, слова)
звірити("verify.СІМ_Ї_СЛІВ", {с for сл in V.СІМ_Ї_СЛІВ.values() for с in сл}, слова)
звірити("verify.ВЖИТОК ⊆ ЛЕКСИКОН", set(V.ВЖИТОК) - set(V.ЛЕКСИКОН), set())
звірити("verify.ВІКНА_КРАМНИЦЬ ⊆ ЛЕКСИКОН", set(V.ВІКНА_КРАМНИЦЬ) - set(V.ЛЕКСИКОН), set())
for ф, дозв, без_unknown in (("внутрішня_мова.schema.json", set(), False), ("каталог_розбір.schema.json", set(), False),
                             ("прилади/рядки_5190/відповідь.schema.json", пілотні, True)):
    for шлях, е in переліки(json.load(open(ф, encoding="utf-8"))):
        звірити(ф + шлях, [к for к in е if к != "unknown"], коди, дозв)
# лишилось, що сім'я слова підміняла відтінок: латинське слово крамниці, що є кодом, веде в ІНШЕ слово, ніж цей код
for лат, сл in V.СЛОВА_КРАМНИЦЬ_ЛАТИНКОЮ.items():
    if лат in продукт and продукт[лат] != сл and (СК.ЛАТИНКА_ВИНЯТКИ if СК else {}).get(лат) != сл:
        розходження.append("латинка %r → «%s», а код %s = «%s»" % (лат, сл, лат, продукт[лат]))
# синонім розбору веде в код поза продуктом, не оголошений словником
for син, к in КР._КОЛІР.items():
    if син == "sage" and not СК and к in коди:
        розходження.append("синонім 'sage' → %s: код пілота підмінено сусіднім, заміна не оголошена" % к)
    if к not in коди:
        розходження.append("синонім %r → %r: коду нема в продукті" % (син, к))
    elif СК and син in СК.КОДИ and син != к and СК.ПРОДУКТ_ЗАМІСТЬ.get(син) != к:
        розходження.append("синонім %r → %s: код пілота, заміни в словнику нема" % (син, к))
    elif син in продукт and син != к:
        розходження.append("синонім %r веде в %s, а це код продукту" % (син, к))
# сім'я слова одна в словнику й лексиконі
if СК:
    for с, ім in СК.СІМ_Я.items():
        if V.сім_я_слова(с) not in (None, ім):
            розходження.append("сім'я %r: verify %s, словник %s" % (с, V.сім_я_слова(с), ім))
print("ФАКТ · кодів продукту %d, слів лексикону %d, пілотних кодів поза продуктом %d%s" % (
    len(коди), len(V.ЛЕКСИКОН), len(пілотні), ", словник " + СК.ВЕРСІЯ if СК else ", словника нема"))
for р in розходження:
    print("  РОЗХОДЖЕННЯ ·", р)
print("ФАКТ · розходжень %d" % len(розходження))
