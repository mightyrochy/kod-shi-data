const fs = require('fs'), path = require('path'), crypto = require('crypto');

function sha256(дані){ return crypto.createHash('sha256').update(дані).digest('hex'); }

/* sha256 файла або null, коли файла нема: відсутній вхід — факт запису, а не кидок */
function sha256Файла(шлях){
  try { return sha256(fs.readFileSync(шлях)); } catch (_) { return null; }
}

/* голова git дерева, з якого біжить прилад (код приладу; код продукту — штамп сторінки) */
function головаДерева(тека){
  try {
    return require('child_process').execFileSync('git', ['rev-parse', 'HEAD'],
      {cwd: тека, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore']}).trim() || null;
  } catch (_) { return null; }
}

/* штампи зібраної сторінки: SHA джерел (0.1), відбиток вантажу й назва каталогу — без розбору всього html */
function штампиСторінки(html){
  const взяти = ім => { const м = new RegExp('const ' + ім + ' = "([^"]*)"').exec(html); return м ? м[1] : null; };
  return {збірка: взяти('ЗБІРКА_ПОКАЗУ'), відбиток: взяти('ВІДБИТОК_ПОКАЗУ'), каталог: взяти('КАТАЛОГ_ПОКАЗУ')};
}

function новийRunId(){
  return 'run-' + Date.now().toString(36) + '-' + crypto.randomBytes(4).toString('hex');
}

const пауза = мс => new Promise(р => setTimeout(р, мс));

/* Готовність, а не таймер: `умова` (може бути async) повертає істинне значення — його й віддаємо. */
async function чекатиНа(умова, опис, ліміт = 60000, крок = 25){
  const початок = Date.now();
  let остання = null;
  for (;;){
    try { const з = await умова(); if (з) return з; } catch (e) { остання = e; }
    if (Date.now() - початок >= ліміт)
      throw new Error('не дочекались за ' + ліміт + ' мс: ' + опис + (остання ? ' (' + String(остання.message || остання) + ')' : ''));
    await пауза(крок);
  }
}

class Доказ {
  constructor({прилад, код = null, режим = {}, модель = null, входи = {}, очікувано = {}, run_id = null}){
    this.запис = {формат: 1, прилад, run_id: run_id || новийRunId(), почато: new Date().toISOString(),
                  код: Object.assign({}, код), режим, модель, входи: {}, очікувано: Object.assign({}, очікувано),
                  факт: {}, подія: null, кінець: null};
    for (const [к, в] of Object.entries(входи)) this.вхід(к, в);
  }
  get run_id(){ return this.запис.run_id; }
  /* вхід — шлях до файла (рахується sha256), рядок-вміст `{вміст}` або готовий `{sha256}` */
  вхід(ім, в){
    if (в == null) this.запис.входи[ім] = null;
    else if (typeof в === 'string') this.запис.входи[ім] = {шлях: в, sha256: sha256Файла(в)};
    else if (в.вміст != null) this.запис.входи[ім] = {sha256: sha256(String(в.вміст)), символів: String(в.вміст).length};
    else this.запис.входи[ім] = в;
    return this;
  }
  очікувати(ключ, скільки){ this.запис.очікувано[ключ] = скільки; return this; }
  факт(ключ, скільки){ this.запис.факт[ключ] = скільки; return this; }
  /* подія завершення — назва точки, до якої прогін справді дійшов */
  завершено(подія){ this.запис.подія = подія; this.запис.кінець = new Date().toISOString(); return this; }
  вердикт(){
    const з = this.запис, чому = [];
    if (!з.подія) чому.push('нема події завершення');
    for (const [к, оч] of Object.entries(з.очікувано)){
      const ф = з.факт[к];
      if (ф === undefined || ф === null){ чому.push(к + ': не виміряно'); continue; }
      if (оч && typeof оч === 'object'){
        if (оч.мін != null && !(ф >= оч.мін)) чому.push(к + ' ' + ф + ' < ' + оч.мін);
      } else if (ф !== оч) чому.push(к + ' ' + ф + ' ≠ ' + оч);
    }
    for (const [к, в] of Object.entries(з.входи)) if (!в || (в.шлях && !в.sha256)) чому.push('вхід ' + к + ' не прочитано');
    return {доведено: !чому.length, чому};
  }
  рядок(){
    const в = this.вердикт(), з = this.запис;
    return 'ДОКАЗ · ' + з.прилад + ' · ' + з.run_id + ' · код ' + (з.код.збірка || з.код.дерево || '?')
      + ' · подія ' + (з.подія || '—') + ' · ' + (в.доведено ? 'доведено' : 'НЕ ДОВЕДЕНО: ' + в.чому.join('; '));
  }
  /* JSON поруч із виходами прогону; синхронно — щоб працювало й з `process.on('exit')` */
  записати(шлях){
    if (!шлях) return null;
    fs.mkdirSync(path.dirname(path.resolve(шлях)), {recursive: true});
    fs.writeFileSync(шлях, JSON.stringify(Object.assign({}, this.запис, {вердикт: this.вердикт()}), null, 1) + '\n', 'utf8');
    return шлях;
  }
}

