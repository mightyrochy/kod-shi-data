"""Сторож таблиці каталогу для проб і стендів, що ганяють код ЗІБРАНОЇ сторінки (наряд Проби-таблиця-збірки, 15018–15020).

Продукт мовчки відхиляє таблицю, ключ якої не збігся з кодом чи даними поруч (`таблиця_каталогу._розбіжність` →
`СТАН` «застаріла»/«нема») і будує базу на льоту: вихід той самий, але чужий `мета.таблиця_каталогу`, а час — інший. У
браузері таблиця й код їдуть однією збіркою, тож жінка цього не бачить; проба чи стенд, що підмінив байт модуля, взяв таблицю
з іншої збірки чи розпакував сторінку без таблиці, знімав числа на шляху, яким продукт не ходить, — і не знав про це.

`розбіжність(тека)` — той самий вирок, що `_розбіжність`, лише для коду й даних ключа (фід у теці сторінки не лежить:
його дає виклик): рядок-причина або None. `вимагати(тека)` — причина стає зупинкою запуску (SystemExit); повільний шлях —
лише за явною згодою (`дозволити_повільний=True` чи змінна середовища `ТАБЛИЦЯ_ПОВІЛЬНИЙ=1`). Тільки stdlib: файл виконується
і в CPython, і в Pyodide (`знімок_мосту_pyodide.js` кладе його поруч зі `знімок_мосту.py`).
"""
import gzip, hashlib, json, os

ТАБЛИЦЯ = "каталог_таблиця.json.gz"


def _md5(шлях):
    with open(шлях, "rb") as ф:
        return hashlib.md5(ф.read()).hexdigest()


def розбіжність(тека, таблиця=None, фід=None):
    """Чому таблиця не вживеться з кодом теки, рядком; None — ключ збігається з кодом і даними теки. `таблиця` — файл поза текою
    (проба бере таблицю окремо від коду); без неї — `каталог_таблиця.json.gz` поруч, як у вантажі сторінки. `фід` — XML, на
    якому проба відновлює каталог з таблиці: його md5 має збігатися з `ключ.фід` (як у `таблиця_каталогу._розбіжність`)."""
    ш = таблиця or os.path.join(тека, ТАБЛИЦЯ)
    if not os.path.exists(ш):
        return "нема " + (ш if таблиця else "у теці " + ТАБЛИЦЯ)
    try:
        with gzip.open(ш, "rt", encoding="utf-8") as ф:
            ключ = json.load(ф).get("ключ") or {}
    except Exception as е:
        return "таблиця не читається: %s: %s" % (type(е).__name__, str(е)[:200])
    змінено = []
    if фід is not None:
        if not os.path.isfile(фід):
            return "нема фіду " + фід
        if _md5(фід) != ключ.get("фід"):
            return "фід інший (md5 %s, таблиця — %s)" % (_md5(фід)[:12], str(ключ.get("фід"))[:12])
    for м, md5 in sorted((ключ.get("код") or {}).items()):
        файл = os.path.join(тека, м + ".py")
        if not os.path.exists(файл) or _md5(файл) != md5:
            змінено.append(м)
    if змінено:
        return "змінився код побудови: " + ", ".join(змінено)
    for ім, md5 in sorted((ключ.get("дані") or {}).items()):
        файл = os.path.join(тека, ім)
        є = os.path.isfile(файл)
        if md5 is None:
            if є:
                змінено.append(ім + " (з'явився, при побудові його не було)")
        elif not є or _md5(файл) != md5:
            змінено.append(ім)
    if змінено:
        return "змінились дані побудови: " + ", ".join(змінено)
    return None


def вимагати(тека, дозволити_повільний=False, таблиця=None, фід=None):
    """Зупиняє запуск, коли таблиця теки не вживеться, і називає причину; явна згода на повільний шлях — повертає її."""
    чому = розбіжність(тека, таблиця, фід)
    if чому and not (дозволити_повільний or os.environ.get("ТАБЛИЦЯ_ПОВІЛЬНИЙ") == "1"):
        raise SystemExit("таблиця каталогу не вживеться (%s): прогін пішов би повільним шляхом, а не шляхом збірки; "
                         "явна згода — ТАБЛИЦЯ_ПОВІЛЬНИЙ=1" % чому)
    return чому


def явно_без_таблиці(чому):
    """Проба на дереві `джерела/` бере повільний (опорний) шлях свідомо: таблиці там нема за задумом. Це не мовчазний перехід —
    запуск називає шлях у stderr і згоду фіксує змінною, щоб вкладені виклики сторожа не зупиняли його."""
    os.environ["ТАБЛИЦЯ_ПОВІЛЬНИЙ"] = "1"
    import sys
    print("шлях без таблиці (явно): " + чому, file=sys.stderr)
