"""Зміст знімка: рішення мосту доменною мовою (крок 0.2-Б; мірило Ф2: «різниця = виміряне розходження»).

Знімок `знімок_мосту.py` порівнює шляхи JSON по викликах і не каже, що змінилось у рішенні. Тут той самий знімок читається як
рішення продукту: паспорт нагоди (поля кодами), поломка і сід руки 2, пул кожної руки (id за слотами), палітра, обраний образ
кожної руки (id речей), знахідки суду (правило, регістр, сила, `сила_нп`), картки (речі й порядок), промпти (довжина, хеш),
«Оціни мій образ». Усе беруть з результатів викликів: окремого запису входів не треба.

  python3 джерела/прилади/знімок_мосту.py зміст знімок.jsonl [--json зміст.json]
  python3 джерела/прилади/знімок_мосту.py зміст --діф а.jsonl б.jsonl [--ліміт 30]   # лічба змін за розділом і типом

Розділ — список записів `{н, …}` (н — номер виклику у знімку): два знімки одних входів мають однакові номери, тож записи
порівнюються за `(розділ, н)`. Типи змін: `додано`, `вилучено`, `значення` (скаляр), `склад` (інший набір id), `порядок`
(той самий набір id в іншому порядку), `довжина` і `хеш` (промпт: довжина різна; довжина та сама, текст інший)."""
import hashlib, json, sys

ФОРМАТ_ЗМІСТУ = 1
ПРОЗА_ПАСПОРТА = {'відповідь_людині', 'порада_людині', 'порада_не_озвучена', 'поради_дані', 'питання_людині', 'слова',
                  'подія', 'поля_шару', 'помилка_формату'}


def хеш(текст):
    return hashlib.sha256(текст.encode('utf-8')).hexdigest()[:12]


def ознака(текст):
    """Промпт чи довгий текст — `[довжина, хеш]`: за тим, що змінилось, видно «текст чи тільки його довжину»."""
    текст = текст if isinstance(текст, str) else json.dumps(текст, ensure_ascii=False, sort_keys=True)
    return [len(текст), хеш(текст)]


def взяти(о, *шлях, типово=None):
    for к in шлях:
        if not isinstance(о, dict) or к not in о:
            return типово
        о = о[к]
    return о


def знахідки(список):
    """Знахідки суду: правило, регістр, сила, `сила_нп` — без довгих пояснень; речі — id."""
    return [{'правило': з.get('правило'), 'регістр': з.get('регістр'), 'сила': з.get('сила'), 'сила_нп': з.get('сила_нп'),
             'речі': list(з.get('речі') or [])} for з in (список or []) if isinstance(з, dict)]


def рука_виклику(р):
    """Рука виклику `від_моделі`: проза без каталогу — руки 3–4 (які саме, з виходу не видно); образи з каталогу — рука 2, коли є
    вимір розбіжності пулу з рукою 1 (`палітра.пара_руки` несе `pool_diff`), інакше рука 1."""
    if 'без каталогу' in (р.get('джерело_образу') or ''):
        return '3|4'
    return '2' if 'pool_diff' in str(взяти(р, 'палітра', 'пара_руки')) else '1'


def запис_паспорта(п):
    return {к: v for к, v in sorted((п or {}).items()) if к not in ПРОЗА_ПАСПОРТА}


def запис_поломки(р):
    п = р.get('поломка') or {}
    return {'назва': п.get('назва'), 'поломок': п.get('поломок'), 'коди': п.get('коди'), 'діє': п.get('діє'),
            'аспекти': п.get('аспекти'), 'поломки_руки_2': р.get('поломки_руки_2'),
            'сід_рук': {к: взяти(р, 'порядок_рук', к, 'сід') for к in ('1', '2')}}


def пули_рук(р):
    """Пул руки — id за слотами в тому порядку, у якому їх бере композитор (`порядок_рук`); руки 3–4 каталогу не мають."""
    return [{'рука': рука, 'слоти': {сл: list(ід) for сл, ід in sorted((взяти(р, 'порядок_рук', рука, 'слоти') or {}).items())}}
            for рука in ('1', '2') if взяти(р, 'порядок_рук', рука, 'слоти')]


def запис_образу(о):
    return {'номер': о.get('номер'), 'вузол': о.get('вузол'), 'підпис': о.get('підпис'), 'ід': list(о.get('ід') or []),
            'речі_н': list(о.get('речі_н') or []), 'схема': взяти(о, 'риси', 'схема'),
            'свідомі': [с.get('ід') for с in (о.get('свідомі') or []) if isinstance(с, dict)],
            'перевірено': о.get('перевірено'), 'знахідки': знахідки(о.get('знахідки'))}


def запис_руки(н, р):
    п = р.get('палітра') or {}
    return {'н': н, 'рука': рука_виклику(р), 'джерело': р.get('джерело_образу'), 'чому': р.get('чому'),
            'перевірено': р.get('перевірено'), 'образів': len(р.get('образи') or []),
            'образи': [запис_образу(о) for о in (р.get('образи') or []) if isinstance(о, dict)],
            'знахідки': знахідки(р.get('знахідки')), 'блокує': list(р.get('блокує') or []),
            'палітра': {к: п.get(к) for к in ('схема', 'база', 'правило_руки', 'поломки', 'пара_руки') if к in п},
            'проза': ознака(р['проза_руки']) if р.get('проза_руки') else None}


def запис_палітри(н, р):
    основи = р.get('основи') or {}
    return {'н': н, 'вибір_кольору': р.get('вибір_кольору'), 'схеми': [г.get('схема') for г in (р.get('гілки') or [])
            if isinstance(г, dict)], 'рекомендовані': [о.get('ключ') for о in (основи.get('рекомендовані') or [])
            if isinstance(о, dict)], 'метал': основи.get('метал'), 'контраст': взяти(р, 'контраст', 'рівень'),
            'намір': р.get('намір'), 'радить_код': р.get('радить_код')}


def запис_вибору_палітри(н, р):
    if 'промпт' in р:
        return {'н': н, 'крок': 'промпт', 'лишила': р.get('лишила'), 'основ': р.get('основ'), 'схем': р.get('схем'),
                'промпт': ознака(р['промпт'])}
    в = р.get('вибір') or {}
    return {'н': н, 'крок': 'вибір', 'схема': в.get('схема'), 'гама': в.get('гама'), 'основа_ранг': в.get('основа_ранг'),
            'ранг_схеми': в.get('ранг_схеми'), 'вибір_кольору': в.get('вибір_кольору'), 'обрала': в.get('обрала'),
            'відхилено': р.get('відхилено'), 'знахідки': знахідки(р.get('знахідки')), 'без_моделі': р.get('без_моделі')}


def запис_картки(н, р):
    о = р.get('опис') or {}
    return {'н': н, 'образ': взяти(о, 'образ', 'ід'), 'речі': [т.get('id') for т in (р.get('речі') or [])],
            'підписи': len(р.get('підписи') or []), 'фото': р.get('усього_фото'), 'задум': ознака(о.get('задум') or ''),
            'промпт': ознака(р.get('промпт') or '')}


import колір_річ as _КОЛІР
def запис_оцінки(н, р):
    """Усі кроки «Оціни мій образ»: речі з фото, суд (знахідки, зміни), відповідь картки."""
    з = {'н': н, 'ключі': sorted(р)}
    суд = р.get('суд')
    if 'промпт' in р:
        з['промпт'] = ознака(р['промпт'])
    if isinstance(суд, dict) and 'findings' in суд:
        з['суд'] = знахідки(суд['findings'])
        з['рівень'] = р.get('рівень')
        з['образ'] = list(р.get('образ') or [])
        з['зміни'] = [{'вид': м.get('вид'), 'нова': м.get('нова'), 'знято': м.get('знято'), 'дельта': м.get('дельта')}
                      for м in (р.get('зміни') or []) if isinstance(м, dict)]
        з['конфлікти'] = len(р.get('конфлікти') or [])
    ккт = р.get('картка')
    if isinstance(ккт, dict):
        з['вердикт'] = ккт.get('вердикт')
        з['вдало'] = len(ккт.get('вдало') or [])
        з['змінити'] = len(ккт.get('змінити') or [])
    if isinstance(р.get('речі'), list):
        з['речі'] = [{'слот': т.get('слот'), 'назва': т.get('назва'), 'колір': т.get('колір')} if isinstance(т, dict) else т
                     for т in р['речі']]
    if 'hex' in р:
        з['hex'] = _КОЛІР.hex_кольору(р)
    return з


def запис_мови(н, р):
    if 'промпт' in р:
        return {'н': н, 'промпт': ознака(р['промпт']), 'вибірка': р.get('вибірка')}
    з = {'н': н, 'ключі': sorted(р), 'ознака': ознака(р)}
    if isinstance(р.get('внутрішня'), dict):
        з['внутрішня'] = р['внутрішня']
    return з


ПРОМПТИ_ЗАПИТІВ = ('B', 'C', 'В', 'Г', 'перелік_прози')


def зміст(текст_знімка):
    """Знімок (JSONL) → зміст: розділи-списки записів `{н, …}`. Помилки викликів — окремий розділ."""
    рядки = [json.loads(р) for р in текст_знімка.splitlines() if р.strip()]
    шапка, виклики = рядки[0], рядки[1:]
    з = {к: [] for к in ('паспорти', 'поломки', 'пули', 'промпти', 'палітри', 'вибір_палітри', 'руки', 'картки', 'показ',
                         'оцінки', 'мова', 'вердикти', 'помилки')}
    з.update({'формат': ФОРМАТ_ЗМІСТУ, 'входи_sha256': шапка['входи_sha256'], 'викликів': len(виклики)})
    for в in виклики:
        н, ім, р = в['н'], в['ім'], в.get('результат')
        if 'помилка' in в:
            з['помилки'].append({'н': н, 'ім': ім, 'помилка': в['помилка']})
        elif ім == 'запити' and isinstance(р, dict):
            з['паспорти'].append({'н': н, **запис_паспорта(р.get('паспорт'))})
            з['поломки'].append({'н': н, **запис_поломки(р)})
            з['пули'] += [{'н': н, **п} for п in пули_рук(р)]
            з['промпти'].append({'н': н, 'виклик': ім, **{к: ознака(р[к]) for к in ПРОМПТИ_ЗАПИТІВ if р.get(к)}})
        elif ім == 'від_моделі' and isinstance(р, dict):
            з['руки'].append(запис_руки(н, р))
        elif ім == 'палітри' and isinstance(р, dict):
            з['палітри'].append(запис_палітри(н, р))
        elif ім == 'вибір_палітри' and isinstance(р, dict):
            з['вибір_палітри'].append(запис_вибору_палітри(н, р))
        elif ім == 'опис' and isinstance(р, dict):
            з['картки'].append(запис_картки(н, р))
        elif ім == 'показ' and isinstance(р, list):
            з['показ'].append({'н': н, 'ід': [т.get('id') for т in р if isinstance(т, dict)]})
        elif ім == 'оцінка' and isinstance(р, dict):
            з['оцінки'].append(запис_оцінки(н, р))
        elif ім == 'мова' and isinstance(р, dict):
            з['мова'].append(запис_мови(н, р))
        elif ім == 'вердикт':
            з['вердикти'].append({'н': н, 'ознака': ознака(р)})
    return з


def текстом(з):
    """Коротко рядками, для очей: що вирішено в цій сцені."""
    р = ['викликів %d · входи %s…' % (з['викликів'], з['входи_sha256'][:10])]
    for п in з['паспорти']:
        р.append('паспорт н=%d: нагода %s · місце %s · дрес-код %s · ошатність %s · година %s · темп %s · опади %s · намір %s · вето %s'
                 % (п['н'], п.get('нагода'), п.get('місце'), п.get('дрес_код'), п.get('ошатність'), п.get('година'),
                    п.get('темп_c'), п.get('опади'), п.get('намір'), json.dumps(п.get('вето'), ensure_ascii=False)))
    for п in з['поломки']:
        р.append('поломка руки 2 н=%d: «%s» (поломок %s) · коди %s · сід рук 1/2: %s/%s'
                 % (п['н'], п.get('назва'), п.get('поломок'), п.get('коди'), п['сід_рук'].get('1'), п['сід_рук'].get('2')))
    for п in з['пули']:
        р.append('пул н=%d рука %s: слотів %d · id %d (%s)' % (п['н'], п['рука'], len(п['слоти']),
                 sum(len(v) for v in п['слоти'].values()), ', '.join('%s %d' % (с, len(v)) for с, v in п['слоти'].items())))
    for п in з['палітри']:
        р.append('палітра н=%d: база %s · схеми %s · рекомендованих основ %d · контраст %s' % (
            п['н'], (п.get('вибір_кольору') or {}).get('база'), ','.join(map(str, п['схеми'])), len(п['рекомендовані']), п.get('контраст')))
    for п in з['вибір_палітри']:
        р.append('вибір палітри н=%d (%s): схема %s · гама %s · обрала %s' % (п['н'], п['крок'], п.get('схема'), п.get('гама'),
                 json.dumps(п.get('обрала'), ensure_ascii=False)))
    for п in з['руки']:
        обр = '; '.join('%s[%s]' % (о['номер'], ' '.join(map(str, о['ід'] or о['речі_н']))) for о in п['образи'][:3])
        р.append('рука %s н=%d: %s · образів %d · знахідок суду %d · перевірено %s · %s' % (
            п['рука'], п['н'], п['джерело'] or '—', п['образів'], len(п['знахідки']), п['перевірено'], обр))
    for п in з['картки']:
        р.append('картка н=%d: образ %s · речі %s' % (п['н'], п['образ'], ' '.join(map(str, п['речі']))))
    for п in з['оцінки']:
        р.append('оцінка н=%d: %s' % (п['н'], ' · '.join('%s=%s' % (к, json.dumps(п[к], ensure_ascii=False)[:90])
                                                         for к in ('вердикт', 'рівень', 'суд', 'зміни') if к in п) or ','.join(п['ключі'])))
    р.append('промпти: ' + ', '.join('н=%d %s' % (п['н'], ' '.join('%s %d/%s' % (к, v[0], v[1]) for к, v in п.items()
                                                                  if isinstance(v, list))) for п in з['промпти']))
    р.append('мова: %d викликів · вердиктів %d · помилок %d' % (len(з['мова']), len(з['вердикти']), len(з['помилки'])))
    return '\n'.join(р)


def за_н(записи):
    """Записи розділу за номером виклику; рядки, що ділять `н` (два пули в одному запиті), нумеруються ключем руки."""
    вих = {}
    for з in записи:
        ключ = (з['н'], з.get('рука')) if 'слоти' in з else з['н']
        вих[ключ] = з
    return вих


def різниця(а, б, шлях, вихід):
    """Лист (шлях, тип, опис) для двох значень одного місця."""
    if а == б:
        return
    if isinstance(а, dict) and isinstance(б, dict):
        for к in sorted(set(а) | set(б), key=str):
            if к not in а or к not in б:
                вихід.append(('%s.%s' % (шлях, к), 'додано' if к in б else 'вилучено', repr(б.get(к, а.get(к)))[:70]))
            else:
                різниця(а[к], б[к], '%s.%s' % (шлях, к), вихід)
    elif (isinstance(а, list) and len(а) == 2 and isinstance(а[1], str) and isinstance(б, list) and len(б) == 2
          and isinstance(б[1], str) and isinstance(а[0], int)):
        вихід.append((шлях, 'довжина' if а[0] != б[0] else 'хеш', '%d≠%d' % (а[0], б[0]) if а[0] != б[0] else а[1] + '≠' + б[1]))
    elif isinstance(а, list) and isinstance(б, list) and all(isinstance(x, str) or x is None for x in а + б):
        if sorted(map(str, а)) == sorted(map(str, б)):
            вихід.append((шлях, 'порядок', '%d id' % len(а)))
        else:
            вихід.append((шлях, 'склад', '+%d −%d' % (len(set(map(str, б)) - set(map(str, а))), len(set(map(str, а)) - set(map(str, б))))))
    elif isinstance(а, list) and isinstance(б, list):
        for i in range(max(len(а), len(б))):
            if i >= len(а) or i >= len(б):
                вихід.append(('%s[%d]' % (шлях, i), 'додано' if i >= len(а) else 'вилучено', ''))
            else:
                різниця(а[i], б[i], '%s[%d]' % (шлях, i), вихід)
    else:
        вихід.append((шлях, 'значення', '%s ≠ %s' % (repr(а)[:40], repr(б)[:40])))


def діф_змісту(а, б):
    """Зміни двох змістів: [(розділ, тип, шлях, опис)]."""
    вих = []
    for розділ in sorted(к for к, v in а.items() if isinstance(v, list)):
        са, сб = за_н(а[розділ]), за_н(б.get(розділ, []))
        for ключ in sorted(set(са) | set(сб), key=str):
            if ключ not in са or ключ not in сб:
                вих.append((розділ, 'додано' if ключ in сб else 'вилучено', '[н=%s]' % (ключ,), ''))
                continue
            знайдене = []
            різниця(са[ключ], сб[ключ], '[н=%s]' % (ключ,), знайдене)
            вих += [(розділ, тип, шлях, опис) for шлях, тип, опис in знайдене]
    return вих


def прочитати_зміст(шлях):
    текст = open(шлях, encoding='utf-8').read()
    return json.loads(текст) if шлях.endswith('.json') else зміст(текст)


def діф(шлях_а, шлях_б, ліміт=30):
    """Друкує лічбу змін за розділом і типом і перші `ліміт` змін; повертає кількість змін."""
    зміни = діф_змісту(прочитати_зміст(шлях_а), прочитати_зміст(шлях_б))
    лічба = {}
    for розділ, тип, _, _ in зміни:
        лічба[(розділ, тип)] = лічба.get((розділ, тип), 0) + 1
    print('змін у змісті: %d%s' % (len(зміни), ' · зміст тотожний' if not зміни else ''))
    for (розділ, тип), к in sorted(лічба.items()):
        print('  %-14s %-9s %d' % (розділ, тип, к))
    for розділ, тип, шлях, опис in зміни[:ліміт]:
        print('  %s %s %s %s' % (розділ, шлях, тип, опис))
    return len(зміни)


