"""Вимір на фото: відношення ширини виробу до ширини торса на рівні грудей (наряд 6.5, п.1; корінь: константа бази
жилета брали з наявного припуску, а не з фото). Лише PIL + numpy: без мережі й без моделей.

Що міряє. Виріб на кадрі виділяємо за кольором, торс крізь виріб не видно, тож його ширина береться з мір моделі
в картці (обхват грудей / π — так само, як ширину тіла в `силует_крої`) і масштабу кадра. Відношення = ширина виробу
на рівні грудей / ширина торса на рівні грудей, обидві в пікселях кадра.

Правило (усе числами нижче, не оком):
  1. Маска виробу — Lab-гауссова модель кольору за вікном (2·R+1)² навколо насіння (точка на виробі, дає людина чи
     картка): піксель у виробі, якщо відстань Махаланобіса до середнього < K·√3; σ знизу обмежена `СИГМА_МІН`
     (однорідна тканина інакше дає σ≈0). Дірки закриваємо (`ЗАКРИТТЯ` зсувів вшир і вузько), лишаємо компоненту насіння.
  2. Рядок виробу — [найлівіший, найправіший] піксель маски в рядку; ширина — їхня різниця + 1.
  3. Верх виробу — перший рядок, де кількість пікселів маски ≥ `ЧАСТКА_ВЕРХУ` (0,35) медіани цієї кількості в рядках
     5–25 % висоти маски (бретелі не рахуємо, а розкльошена спідниця не зсуває верх, як зсувала б частка максимуму); низ — останній
     рядок із шириною ≥ `ЧАСТКА_НИЗУ` (0,35) максимуму. Довжина L = низ − верх + 1.
  4. Рівень грудей — верх + `ГРУДИ_СМ` (20 см) · масштаб: лінія грудей для зросту 165–175 см лежить ≈ 20 см нижче
     верху виробу (плеча/коміра); у см, а не в частці довжини, бо довгий виріб (сарафан, жилет-пальто) зсунув би
     частку на талію. Ширина на рівні — медіана ширин у смузі ±`СМУГА` рядків. Чутливість до рівня —
     `--чутливість` (17…26 см) у висновку.
  5. Масштаб — L / довжина виробу з таблиці розмірів (см) або `--масштаб` (пікс/см), якщо відомий інакше.
     Ширина торса = груди_см / π · масштаб.

Межі правила (тому в PR — діапазон, не точка): поза 3/4 стискає виріб на кадрі й занижує відношення; мозаїка 1200×360
дає ~45 px ширини торса, тож ±1 px ≈ ±2…5 %; витік маски в одяг того самого кольору подовжує L й завищує масштаб.
Перевірка на відомому (PR #1723): тугий корсетний бодис сукні a-line — 0,97 (очікується ≈1,0), але тугий трикотажний топ
дає 1,58: торс береться за колом (обхват/π), а на кадрі це фронтальна проекція (еліпс + зона пахв), тож абсолют
завищено до ×1,5 і між кадрами він не переноситься. Число придатне як порівняння жилетів між собою й із таблицею,
не як окремий еталон. На друкованій тканині (квітковий сарафан) і на сукні з різним тоном ліфа й спідниці маска
витікає в тло чи рветься — потрібна `--коробка` й часом більший `--k`; такі кадри для виміру не брались.

  python3 джерела/прилади/ширина_торса.py <кадр> --насіння X Y --груди-см 83 --довжина-см 63 \\
          [--коробка x0 y0 x1 y1] [--вихід-маска маска.png] [--чутливість]
Без довжини виробу в картці — `--зріст-см 175 --комірка x0 y0 x1 y1 --фон X Y` (студійний кадр на рівному тлі).
Кадри — з гілки `claude/zhyvi-32` за шляхом (`git show origin/claude/zhyvi-32:аудит/фото_32/a-line/<файл> > /tmp/…`),
у репозиторій не копіюються. Координати насіння й коробки — абсолютні, в пікселях файлу."""
import argparse, math, sys

import numpy as np
from PIL import Image

R_ВІКНА = 4
K = 3.0
СИГМА_МІН = 4.0
ЗАКРИТТЯ = 2
ВЕРХ_ЗОНА = (0.05, 0.25)
ЧАСТКА_ВЕРХУ = 0.35
ЧАСТКА_НИЗУ = 0.35
ГРУДИ_СМ = 20.0
СМУГА = 3
ФІГУРА_МІН = 3


def _розширити(m):
    y = m.copy()
    y[1:] |= m[:-1]
    y[:-1] |= m[1:]
    y[:, 1:] |= m[:, :-1]
    y[:, :-1] |= m[:, 1:]
    return y


def _закрити(m, n):
    for _ in range(n):
        m = _розширити(m)
    for _ in range(n):
        m = ~_розширити(~m)
    return m


def _компонента(m, насіння):
    """Зв'язна (4) компонента насіння (x, y): прохід у ширину без рекурсії."""
    H, W = m.shape
    вих = np.zeros_like(m)
    стек = [(насіння[1], насіння[0])]
    while стек:
        y, x = стек.pop()
        if y < 0 or x < 0 or y >= H or x >= W or вих[y, x] or not m[y, x]:
            continue
        вих[y, x] = True
        стек += [(y + 1, x), (y - 1, x), (y, x + 1), (y, x - 1)]
    return вих


def маска_виробу(im, насіння, коробка=None, k=K):
    """Булева маска виробу на зображенні (повнорозмірна; поза `коробка` — хиба). Коробка — (x0, y0, x1, y1)."""
    a = np.asarray(im.convert("RGB").convert("LAB")).astype(float)
    sx, sy = насіння
    вікно = a[sy - R_ВІКНА:sy + R_ВІКНА + 1, sx - R_ВІКНА:sx + R_ВІКНА + 1].reshape(-1, 3)
    mu = вікно.mean(0)
    sd = np.maximum(вікно.std(0), СИГМА_МІН)
    d = np.sqrt((((a - mu) / sd) ** 2).sum(-1))
    m = d < k * math.sqrt(3)
    if коробка:
        x0, y0, x1, y1 = коробка
        вирізка = np.zeros_like(m)
        вирізка[y0:y1, x0:x1] = True
        m &= вирізка
    return _компонента(_закрити(m, ЗАКРИТТЯ), насіння)


def _ширини(m):
    """Ширина рядка (правий − лівий + 1) для кожного рядка; 0, де маски нема."""
    ширина = np.zeros(m.shape[0], int)
    for y in np.where(m.any(1))[0]:
        xs = np.where(m[y])[0]
        ширина[y] = xs[-1] - xs[0] + 1
    return ширина


def виміряти(im, насіння, груди_см, довжина_см=None, масштаб=None, коробка=None, k=K, груди_від_верху_см=ГРУДИ_СМ):
    """Вимір одного кадра. Повертає словник: ширина_виробу_px, ширина_торса_px, відношення, рядок_грудей, верх, низ,
    довжина_px, масштаб_пксм, маска. Масштаб — з `довжина_см` (довжина виробу в таблиці) або явний `масштаб` (пікс/см)."""
    m = маска_виробу(im, насіння, коробка, k)
    ш = _ширини(m)
    if not ш.any():
        raise ValueError("маска порожня: насіння поза виробом чи поріг замалий")
    н = m.sum(1)
    ряд = np.where(н > 0)[0]
    h = ряд[-1] - ряд[0] + 1
    зона = н[ряд[0] + int(ВЕРХ_ЗОНА[0] * h):ряд[0] + int(ВЕРХ_ЗОНА[1] * h) + 1]
    верх = int(np.where(н >= ЧАСТКА_ВЕРХУ * np.median(зона))[0][0])
    низ = int(np.where(ш >= ЧАСТКА_НИЗУ * ш.max())[0][-1])
    L = низ - верх + 1
    if масштаб is None:
        if not довжина_см:
            raise ValueError("потрібна довжина_см (довжина виробу в таблиці) або масштаб")
        масштаб = L / довжина_см
    y = верх + int(round(груди_від_верху_см * масштаб))
    ширина_виробу = float(np.median(ш[y - СМУГА:y + СМУГА + 1]))
    ширина_торса = груди_см / math.pi * масштаб
    return {"ширина_виробу_px": ширина_виробу, "ширина_торса_px": ширина_торса,
            "відношення": ширина_виробу / ширина_торса, "рядок_грудей": y, "верх": верх, "низ": низ,
            "довжина_px": L, "масштаб_пксм": масштаб, "маска": m}


def масштаб_зі_зросту(im, комірка, зріст_см, фон):
    """Пікс/см за зростом моделі, коли довжини виробу в картці нема (студійний кадр на рівному тлі, модель на повний
    зріст). Фон — Lab-гаусова модель вікна навколо точки `фон`; фігура — решта комірки; висота — від першого до
    останнього рядка, де фігури ≥ `ФІГУРА_МІН` пікселів (волосся зверху, підошва знизу; підошва/каблук ≈ 3–5 см
    зросту відкинуті в мінус масштабу — похибка ≈ 2–3 %)."""
    x0, y0, x1, y1 = комірка
    ф = маска_виробу(im, фон, комірка, K)
    ф[:y0], ф[y1:], ф[:, :x0], ф[:, x1:] = False, False, False, False
    фігура = ~ф
    фігура[:y0], фігура[y1:], фігура[:, :x0], фігура[:, x1:] = False, False, False, False
    рядки = np.where(фігура.sum(1) >= ФІГУРА_МІН)[0]
    return (рядки[-1] - рядки[0] + 1) / зріст_см, int(рядки[0]), int(рядки[-1])


def зберегти_маску(im, m, шлях, вирізка=None):
    ov = np.asarray(im.convert("RGB")).copy()
    ov[m] = (ov[m] * 0.4 + np.array([255, 0, 255]) * 0.6).astype(np.uint8)
    out = Image.fromarray(ov)
    if вирізка:
        out = out.crop(вирізка)
    out.save(шлях)


def _головна(арг=None):
    р = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    р.add_argument("кадр")
    р.add_argument("--насіння", nargs=2, type=int, required=True, metavar=("X", "Y"))
    р.add_argument("--груди-см", type=float, required=True, dest="груди")
    р.add_argument("--довжина-см", type=float, dest="довжина")
    р.add_argument("--масштаб", type=float, help="пікс/см, якщо відомий інакше, ніж за довжиною виробу")
    р.add_argument("--коробка", nargs=4, type=int, metavar=("x0", "y0", "x1", "y1"))
    р.add_argument("--зріст-см", type=float, dest="зріст", help="замість довжини виробу: масштаб за зростом моделі")
    р.add_argument("--комірка", nargs=4, type=int, metavar=("x0", "y0", "x1", "y1"), help="кадр у мозаїці (для зросту)")
    р.add_argument("--фон", nargs=2, type=int, metavar=("X", "Y"), help="точка на рівному тлі (для зросту)")
    р.add_argument("--k", type=float, default=K)
    р.add_argument("--вихід-маска")
    р.add_argument("--чутливість", action="store_true", help="повторити для рівня 17/20/23/26 см від верху")
    а = р.parse_args(арг)
    im = Image.open(а.кадр).convert("RGB")
    if а.зріст:
        а.масштаб, ф0, ф1 = масштаб_зі_зросту(im, а.комірка, а.зріст, tuple(а.фон))
        print("масштаб за зростом %.0f см: фігура рядки %d–%d, %.3f px/см" % (а.зріст, ф0, ф1, а.масштаб))
    рез = виміряти(im, tuple(а.насіння), а.груди, а.довжина, а.масштаб, а.коробка, а.k)
    print("%s | виріб %.1f px | торс %.1f px | відношення %.3f | L=%d px (рядки %d–%d), масштаб %.3f px/см, рядок грудей %d" % (
        а.кадр.rsplit("/", 1)[-1], рез["ширина_виробу_px"], рез["ширина_торса_px"], рез["відношення"],
        рез["довжина_px"], рез["верх"], рез["низ"], рез["масштаб_пксм"], рез["рядок_грудей"]))
    if а.чутливість:
        print("чутливість до рівня від верху: " + "  ".join(
            "%g см→%.3f" % (ч, виміряти(im, tuple(а.насіння), а.груди, а.довжина, а.масштаб, а.коробка, а.k, ч)["відношення"])
            for ч in (17, 20, 23, 26)))
    if а.вихід_маска:
        зберегти_маску(im, рез["маска"], а.вихід_маска, а.коробка)


if __name__ == "__main__":
    _головна()
