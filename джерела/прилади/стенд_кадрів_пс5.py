# -*- coding: utf-8 -*-
"""Наряд ПС-5: ДО (вимір одного головного кадру) → ПІСЛЯ (`жнива_колір.звести_кадри` з усіх кадрів) на збережених файлах.

ЧИТАЄ: `аудит/проби/пс5_кадри/` (`кадри.json`, кадри, маски ATR, мітки ATR — пише `прилади/кадри_поверхні_пс5.py`).
Мовної моделі й мережі не кличе; слово моделі в `звести_колір` — None (його вибір кластера ПС-5 прибрав, а запису
слова моделі для цих речей нема), клас плитки аркуша — невідомо (усі кадри — кадри речі).
ДРУКУЄ і пише `після.json`: на річ — ДО і ПІСЛЯ (слово, hex, сім'я), сім'я слова крамниці, кадри (придатний,
головний hex, згода), розкид і чужі кадри; підсумок — розбіжність виміру з крамницею ДО → ПІСЛЯ (сім'я тону; колір
за вікном слова крамниці — окремо, бо він збігається зі словом за побудовою) і шум виміру: ΔE00 між головними
поверхнями кадрів однієї речі (усі пари придатних і лише згідні) проти порогів суду з реєстрів.
З `--аркуші` — `аркуш_NN.jpg` по 10 речей: кадри з контуром маски, плашка головної поверхні кадру (рамка — згідний),
ДО, ПІСЛЯ, слово крамниці — для очей.
Запуск: cd джерела && python3 -W ignore прилади/стенд_кадрів_пс5.py [--аркуші]
"""
import argparse, itertools, json, os, sys
ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, ТУТ); os.chdir(ТУТ)
ТЕКА = os.path.join(os.path.dirname(ТУТ), "аудит", "проби", "пс5_кадри")
import colorspace as CS, verify as V
from жнива_колір import виміряти_поверхню, звести_колір, звести_кадри, _згодні
V_НЕЙТРАЛЬ = 8.0      # C* «нейтралі» лише для розкладу шуму стенда (міра, не продукт)


def читати(шлях, прапор=None):
    import cv2, numpy as np
    if not os.path.exists(шлях):
        return None
    сирі = np.fromfile(шлях, dtype="uint8")
    return cv2.imdecode(сирі, cv2.IMREAD_COLOR if прапор is None else прапор)


def поверхня(ключ, джерело):
    """Вимір поверхні кадру з файлів; маски нема — None."""
    import cv2
    bgr = читати(os.path.join(ТЕКА, ключ + ".jpg"))
    м = читати(os.path.join(ТЕКА, ключ + ".маска.png"), cv2.IMREAD_GRAYSCALE)
    if bgr is None or м is None:
        return None
    арр = читати(os.path.join(ТЕКА, ключ + ".atr.png"), cv2.IMREAD_GRAYSCALE)
    return виміряти_поверхню(bgr, м, арр, джерело=джерело)


def сім(слово):
    return V.сім_я_слова(слово) if слово else None


def основний(п, слова):
    """Основний колір `звести_колір` з поверхні: [слово, hex, тип] або None."""
    if not п or not п["придатна"]:
        return None
    о = звести_колір(п["сегменти"], None, слова)[0]
    return о and [о["слово"], о["hex"], о.get("колір_тип") or ("вимір" if о.get("тон") is not None else "невідомо")]


def перцентилі(с):
    с = sorted(с)
    if not с:
        return None
    q = lambda p: round(с[min(len(с) - 1, int(p / 100 * len(с)))], 1)
    return dict(n=len(с), p50=q(50), p90=q(90), p95=q(95), p99=q(99), макс=round(с[-1], 1))


def пороги():
    """Пороги суду, що порівнюють виміряні кольори двох речей (ΔE00 / ΔL*), — з реєстрів, не копією."""
    import аксесуари_реєстр as АР, реєстр_константи as РК
    в = {}
    for м, імена in ((АР, ("ΔE_точний_збіг", "ΔE_шум_фото")), (РК, ("ΔE_шум_нейтралей", "ΔL_шум_нейтралей", "step_min"))):
        C = getattr(м, "C", None) or getattr(м, "РЕЄСТР", {})
        for ім in імена:
            з = C.get(ім) if isinstance(C, dict) else None
            в[ім] = з["val"] if isinstance(з, dict) else з
    return в


def main():
    ап = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ап.add_argument("--аркуші", action="store_true")
    ап.add_argument("--змінені", action="store_true", help="аркуші лише речей, де ДО ≠ ПІСЛЯ (змінені_NN.jpg)")
    ап.add_argument("--розбіжні", action="store_true", help="аркуші речей, де виміряна сім'я ПІСЛЯ ≠ крамниці")
    а = ап.parse_args()
    дані = json.load(open(os.path.join(ТЕКА, "кадри.json"), encoding="utf-8"))
    вих, усі_пари, згідні_пари = [], [], []
    шум = {"нейтралі_ΔE00": [], "нейтралі_ΔL": [], "хроматичні_ΔE00": []}   # згідні пари однотонних поверхонь
    for р in дані["речі"]:
        пов = [поверхня(к["ключ"], к.get("маска")) if not к.get("помилка") else None for к in р["кадри"]]
        слова = р["слова_крамниці"]
        до = основний(пов[0] if пов else None, слова)
        обрана, кадри = звести_кадри(пов, 0) if пов else (None, None)
        після = основний(обрана, слова)
        гол = {i: п["сегменти"][0] for i, п in enumerate(пов) if п and п["придатна"] and п["сегменти"]}
        for i, j in itertools.combinations(sorted(гол), 2):
            a, b = tuple(гол[i]["lab"]), tuple(гол[j]["lab"])
            d = CS.de00(a, b)
            усі_пари.append(d)
            if _згодні(гол[i], гол[j]):
                згідні_пари.append(d)
                if пов[i]["візерунок"] == пов[j]["візерунок"] == "однотонний":
                    нейтраль = max(CS.lch(a)[1], CS.lch(b)[1]) < V_НЕЙТРАЛЬ
                    шум["нейтралі_ΔE00" if нейтраль else "хроматичні_ΔE00"].append(d)
                    if нейтраль:
                        шум["нейтралі_ΔL"].append(abs(a[0] - b[0]))
        крамниця = сім(слова[0]) if слова else None
        вих.append(dict(ключ=р["ключ"], id=р["id"], слово_крамниці=слова[:1], сім_я_крамниці=крамниця,
                        до=до, сім_я_до=сім(до and до[0]), після=після, сім_я_після=сім(після and після[0]), кадри=кадри,
                        поверхні=[None if i not in гол else [гол[i]["слово"], гол[i]["hex"], гол[i]["розкид"],
                                                              пов[i]["візерунок"]]
                                  for i in range(len(пов))],
                        чому=[(п or {}).get("чому") for п in пов]))

    def розбіжні(ключ):
        """Речі зі словом крамниці, де вимір є і його сім'я інша; колір за вікном слова — окремо."""
        з_виміром = [в for в in вих if в["сім_я_крамниці"] and в[ключ]]
        вимір = [в for в in з_виміром if в[ключ][2] == "вимір"]
        return dict(зі_словом_і_кольором=len(з_виміром), за_вікном_слова=len(з_виміром) - len(вимір),
                    виміряно=len(вимір), розходяться=sum(в["сім_я_крамниці"] != в["сім_я_" + ключ] for в in вимір))
    підсумок = dict(речей=len(вих), до=розбіжні("до"), після=розбіжні("після"),
                    змінено=sum((в["до"] or [None, None])[1] != (в["після"] or [None, None])[1] for в in вих),
                    шум_усі_пари=перцентилі(усі_пари), шум_згідні_пари=перцентилі(згідні_пари),
                    шум_однотонних={к: перцентилі(в) for к, в in шум.items()}, пороги_суду=пороги(),
                    кадрів_згідних=sum((в["кадри"] or {}).get("згідних", 0) for в in вих),
                    кадрів_чужих=sum((в["кадри"] or {}).get("чужих", 0) for в in вих))
    with open(os.path.join(ТЕКА, "після.json"), "w", encoding="utf-8") as ф:
        json.dump(dict(підсумок=підсумок, речі=вих), ф, ensure_ascii=False, indent=1)
    print(json.dumps(підсумок, ensure_ascii=False))
    if а.аркуші:
        аркуші(дані["речі"], вих)
    if а.змінені:
        пари = [(р, в) for р, в in zip(дані["речі"], вих) if (в["до"] or [0, 0])[1] != (в["після"] or [0, 0])[1]]
        аркуші([р for р, _ in пари], [в for _, в in пари], назва="змінені")
    if а.розбіжні:
        пари = [(р, в) for р, в in zip(дані["речі"], вих) if в["після"] and в["після"][2] == "вимір"
                and в["сім_я_крамниці"] and в["сім_я_крамниці"] != в["сім_я_після"]]
        print("розбіжні:", " ".join(в["ключ"] for _, в in пари))
        аркуші([р for р, _ in пари], [в for _, в in пари], назва="розбіжні")


def аркуші(речі, вих, на_аркуш=10, В=150, назва="аркуш"):
    """Аркуші для очей: рядок — річ, кадри з контуром маски й плашкою головної поверхні; праворуч ДО, ПІСЛЯ, крамниця."""
    import cv2, numpy as np
    from PIL import Image, ImageDraw, ImageFont
    try:
        шр = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 13)
    except OSError:
        шр = ImageFont.load_default()
    for н in range(0, len(речі), на_аркуш):
        ряди = []
        for р, в in zip(речі[н:н + на_аркуш], вих[н:н + на_аркуш]):
            пол = Image.new("RGB", (4 * (В * 3 // 4 + 6) + 330, В + 24), "white")
            д = ImageDraw.Draw(пол)
            x = 4
            for i, к in enumerate(р["кадри"]):
                bgr = читати(os.path.join(ТЕКА, к["ключ"] + ".jpg"))
                if bgr is None:
                    continue
                м = читати(os.path.join(ТЕКА, к["ключ"] + ".маска.png"), cv2.IMREAD_GRAYSCALE)
                if м is not None:
                    конт, _ = cv2.findContours((м > 127).astype("uint8"), cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
                    cv2.drawContours(bgr, конт, -1, (255, 0, 255), 2)
                h, w = bgr.shape[:2]
                ш = max(1, int(w * В / h))
                пол.paste(Image.fromarray(cv2.cvtColor(cv2.resize(bgr, (ш, В)), cv2.COLOR_BGR2RGB)), (x, 2))
                п = в["поверхні"][i]
                обрано = в["кадри"] and в["кадри"]["обрано"] == i
                if п:
                    д.rectangle([x, В + 4, x + 40, В + 20], fill=п[1], outline="black" if обрано else None, width=3)
                    д.text((x + 44, В + 5), п[1], fill="black", font=шр)
                else:
                    д.text((x, В + 5), "непридатна", fill="gray", font=шр)
                x += ш + 6
            x = max(x, 4 * (В * 3 // 4 + 6))
            for y, (мітка, к) in enumerate((("ДО", в["до"]), ("ПІСЛЯ", в["після"]))):
                if к:
                    д.rectangle([x, 4 + y * 40, x + 36, 36 + y * 40], fill=к[1])
                д.text((x + 42, 8 + y * 40), "%s: %s" % (мітка, " ".join(map(str, к)) if к else "—"), fill="black", font=шр)
            кд = в["кадри"] or {}
            д.text((x, 88), "%s %s · крамниця: %s" % (в["ключ"], в["id"][:24], (в["слово_крамниці"] or ["—"])[0]),
                   fill="black", font=шр)
            д.text((x, 106), "згідних %s, чужих %s, розкид %s" % (кд.get("згідних"), кд.get("чужих"), кд.get("розкид")),
                   fill="black", font=шр)
            ряди.append(пол)
        аркуш = Image.new("RGB", (max(р.width for р in ряди), sum(р.height for р in ряди)), "white")
        y = 0
        for р in ряди:
            аркуш.paste(р, (0, y))
            y += р.height
        аркуш.save(os.path.join(ТЕКА, "%s_%02d.jpg" % (назва, н // на_аркуш)), quality=80)


if __name__ == "__main__":
    main()
