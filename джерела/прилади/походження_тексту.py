# -*- coding: utf-8 -*-
"""Доводить походження значення, простежуючи його писачів, а не назву поля.

Невідоме походження лишається невідомим. Об'єднання гілок зберігає кожне
можливе джерело; допис коду до її слів утворює інший вид тексту.
"""


class Походження:
    """Зворотний обхід виразів, присвоєнь, параметрів і повернень."""

    def __init__(с, програма, розділити, входи):
        """Приймає лексичну модель та виведені з модуля входи екрана."""
        с.п, с.розділити, с.входи = програма, розділити, входи
        с.кеш, с.стек = {}, set()

    def вираз(с, м, а, б, поля=()):
        """Повертає всі доведені джерела; цикл не доводить типу."""
        ключ = (м.шлях, а, б, поля)
        if ключ in с.кеш:
            return с.кеш[ключ]
        вузол = (м.шлях, а, б)
        if вузол in с.стек:
            return frozenset({'невідоме'})
        с.стек.add(вузол)
        try:
            вих = frozenset(с._вираз(м, а, б, поля))
            с.кеш[ключ] = вих
            return вих
        finally:
            с.стек.remove(вузол)

    def разом(с, м, частини, поля=()):
        """Об'єднує можливі значення гілок без ваг і порогів."""
        вих = set()
        for а, б in частини:
            вих.update(с.вираз(м, а, б, поля))
        return вих or {'невідоме'}

    def _вираз(с, м, а, б, поля):
        """Розбирає оператори й ланцюг доступу до значення."""
        т, пар = м.ток, м.пар
        while а < б and т[а][1] in (';', 'await', 'yield', '...'):
            а += 1
        if а >= б:
            return {'стале'}
        верх = lambda знаки: с.п._верх(т, пар, а, б, знаки)
        if верх(('=>',)) or т[а][1] in ('function', 'class'):
            return {'вузол'}
        питання = верх(('?',))
        if питання:
            рівень, к = 1, питання[0] + 1
            while к < б:
                if т[к][0] == 'p' and т[к][1] in '([{' and к in пар:
                    к = пар[к] + 1
                    continue
                if т[к][1] == '?':
                    рівень += 1
                elif т[к][1] == ':':
                    рівень -= 1
                    if not рівень:
                        break
                к += 1
            return с.разом(м, [(питання[0] + 1, к), (к + 1, б)], поля)
        for оператори in (('||', '??'), ('&&',)):
            позиції = верх(оператори)
            if позиції:
                межі = [а - 1] + позиції + [б]
                частини = [(межі[і] + 1, межі[і + 1]) for і in range(len(межі) - 1)]
                return с.разом(м, частини if оператори[0] != '&&' else частини[-1:], поля)
        if верх(('===', '==', '!==', '!=', '<', '>', '<=', '>=')):
            return {'число'}
        доданки = [і for і in верх(('+',)) if і > а and т[і - 1][1] not in ('(', ',', '=')]
        if доданки:
            межі = [а - 1] + доданки + [б]
            дж = с.разом(м, [(межі[і] + 1, межі[і + 1]) for і in range(len(межі) - 1)])
            if 'її' in дж:
                дж = (дж - {'її'}) | {'складено'}
            return дж
        if верх(('-', '*', '/', '%', '**', '&', '|', '^', '<<', '>>')) or т[а][1] in ('!', '~', '-', '+', '++', '--'):
            return {'число'}
        # Від кінця ланцюга: поле передається писачеві об'єкта, а не
        # класифікується за власним ім'ям.
        if б - а >= 3 and т[б - 2][1] in ('.', '?.') and т[б - 1][0] == 'id':
            поле = т[б - 1][1]
            if поле in ('length', 'size'):
                return {'число'}
            if поле in ('childNodes', 'children', 'firstChild', 'lastChild'):
                return {'вузол'}
            if поле == 'value':
                база = с.вираз(м, а, б - 2)
                if база == {'елемент'}:
                    return {'її'}
            return с.вираз(м, а, б - 2, (поле,) + поля)
        if т[б - 1][1] == ']' and б - 1 in пар and пар[б - 1] > а:
            від = пар[б - 1]
            індекс = т[від + 1:б - 1]
            поле = індекс[0][1] if len(індекс) == 1 and індекс[0][0] == 'str' else '*'
            return с.вираз(м, а, від, (поле,) + поля)
        if т[а][1] == '(' and пар.get(а) == б - 1:
            return с.вираз(м, а + 1, б - 1, поля)
        if т[а][1] in ('{', '[') and пар.get(а) == б - 1:
            частини = с.розділити(т, пар, а + 1, б - 1)
            if т[а][1] == '[':
                return с.разом(м, частини, поля[1:] if поля and поля[0] == '*' else поля)
            значення = []
            for х, у in частини:
                if х + 1 < у and т[х + 1][1] == ':':
                    if not поля or поля[0] == '*' or т[х][1] == поля[0]:
                        значення.append((х + 2, у))
                elif у - х == 1 and (not поля or поля[0] == '*' or т[х][1] == поля[0]):
                    значення.append((х, у))
            дж = с.разом(м, значення, поля[1:] if поля else ())
            # Назва тут має писача: поле об'єкта створене з її вводу.
            # Саме ім'я поля від fetch чи невідомого об'єкта нічого не доводить.
            if поля == ('назва',) and 'її' in дж and дж <= {'її', 'стале', 'число'}:
                дж |= {'назва'}
            return дж
        if т[б - 1][1] == ')' and б - 1 in пар:
            о = пар[б - 1]
            if о > а and т[о - 1][0] == 'id':
                ім = т[о - 1][1]
                арг = с.розділити(т, пар, о + 1, б - 1)
                if ім in ('Number', 'parseInt', 'parseFloat', 'Boolean', 'isNaN', 'isFinite', 'BigInt'):
                    return {'число'}
                if т[а][1] == 'Math':
                    return {'число'}
                if ім in ('fetch', 'postMessage', 'runPython', 'runPythonAsync', 'містП'):
                    return {'модель'}
                if ім in ('$', 'createElement', 'getElementById', 'querySelector'):
                    if поля and поля[0] == 'value':
                        # Читання поля вводу — джерело її слів; приховані ключі
                        # лишаються кодами, якщо тип елемента доведено розміткою.
                        відомі = getattr(с.п, 'елементи', {})
                        ід = т[арг[0][0]][1] if арг and т[арг[0][0]][0] == 'str' else None
                        тип = відомі.get(ід, ('', ''))
                        if тип[0].lower() in ('select', 'option') or 'hidden' in тип[1]:
                            return {'код'}
                        return {'її'} if len(поля) == 1 else {'невідоме'}
                    return {'елемент'} if not поля else {'невідоме'}
                if ім in с.входи:
                    # Повернений елемент уже має текст; append цього елемента
                    # не є другим записом того самого тексту.
                    функції = с.п.цілі(м, о - 1, ім)
                    результати = set().union(*(с.повернення(ф, ()) for ф in функції)) if функції else set()
                    if результати and результати <= {'елемент', 'вузол'}:
                        return результати
                    види = {вид for _, вид in с.входи[ім]}
                    if види <= {'проза', 'збій'}:
                        return {'перевірено'}
                    return с.разом(м, [арг[к] for к, _ in с.входи[ім] if к < len(арг)], поля)
                if ім in ('String', 'encodeURIComponent', 'decodeURIComponent'):
                    return с.разом(м, арг, поля)
                if о >= а + 3 and т[о - 2][1] in ('.', '?.'):
                    база = (а, о - 2)
                    if ім in ('toFixed', 'toPrecision', 'getTime', 'getFullYear', 'indexOf', 'findIndex', 'includes', 'has', 'test'):
                        return {'число'}
                    if ім in ('stringify', 'parse') and т[а][1] == 'JSON':
                        return с.разом(м, арг, поля)
                    if ім in ('trim', 'trimStart', 'trimEnd', 'toString', 'slice', 'substring', 'substr'):
                        return с.вираз(м, *база, поля)
                    if ім in ('replace', 'replaceAll', 'join', 'toLowerCase', 'toUpperCase', 'padStart', 'padEnd'):
                        дж = с.вираз(м, *база, поля)
                        return (дж - {'її'}) | {'складено'} if 'її' in дж else дж
                    if ім in ('filter', 'sort', 'reverse', 'find', 'at', 'pop', 'shift'):
                        return с.вираз(м, *база, поля)
                    if ім in ('json', 'text'):
                        return с.вираз(м, *база, поля) | {'модель'}
                if ім in с.п.за_ім:
                    вих = set()
                    for ф in с.п.цілі(м, о - 1, ім):
                        вих.update(с.повернення(ф, поля))
                    return вих or {'невідоме'}
                return {'невідоме'}
        if б - а == 1:
            вид, зн, _ = т[а]
            if вид == 'num' or зн in ('null', 'undefined', 'true', 'false'):
                return {'число'}
            if вид in ('str', 're'):
                return {'стале'} if not поля else {'невідоме'}
            if вид == 'tpl':
                # Вкладені вирази лексер зберігає окремим списком токенів.
                дж = set()
                for тип, значення in зн:
                    if тип == 's' and значення:
                        дж.add('стале')
                    elif тип == 'e':
                        вкладений = type(м)(м.шлях + '#шаблон' + str(а), значення)
                        вкладений.ключ = lambda і, ім: м.ключ(а, ім)
                        дж.update(с.вираз(вкладений, 0, len(значення)))
                if 'її' in дж and len(зн) > 1:
                    дж = (дж - {'її'}) | {'складено'}
                return дж or {'стале'}
            if вид == 'id':
                if зн in с.п.закріплені:
                    return {'стале'}
                ключ = м.ключ(а, зн)
                вих = set()
                записи = с.п.присв.get(ключ, ())
                for м2, вид_запису, (х, у), _ in записи:
                    if вид_запису != '=': continue
                    вих.update(с.вираз(м2, х, у, поля))
                if not поля and вих and вих <= {'елемент', 'вузол'}:
                    return вих
                for м2, вид_запису, (х, у), _ in записи:
                    if вид_запису == '=': continue
                    вих.update(с.вираз(м2, х, у, поля))
                ф = с.п.ф_за_ід.get(ключ[0])
                if ф:
                    for к, (_, імена) in enumerate(ф.парам):
                        if зн not in імена:
                            continue
                        for м2, арг, _ in с.п.виклики.get(ф.ід, ()):
                            if к < len(арг):
                                вих.update(с.вираз(м2, *арг[к], поля))
                        зв = с.п._зворотний(ф)
                        if к == 0 and isinstance(зв, tuple):
                            вих.update(с.вираз(ф.мод, *зв, ('*',) + поля))
                return вих or {'невідоме'}
        return {'невідоме'}

    def повернення(с, ф, поля):
        """Простежує всі повернення функції до їхніх джерел."""
        м = ф.мод
        if ф.вираз:
            return с.вираз(м, ф.а, ф.б, поля)
        частини = [(і + 1, м.кінець_виразу(і + 1)) for і in range(ф.а, ф.б)
                   if м.ток[і][1] == 'return' and м.охоплює(і) is ф]
        return с.разом(м, частини, поля)


def невідповідний(джерела, вид):
    """Звіряє доведене походження з договором входу без числових порогів."""
    if вид in ('проза', 'збій'):
        return False
    дозволені = {'стале', 'число', 'перевірено'}
    if вид == 'назва':
        дозволені |= {'назва', 'її'}
        if 'назва' in джерела:
            дозволені.add('складено')
    elif вид == 'її':
        # Сталий допис разом із її словами вже позначено «складено».
        дозволені |= {'її', 'назва'}
    else:
        дозволені |= {'її', 'вузол', 'елемент'}
    return not джерела <= дозволені
