# -*- coding: utf-8 -*-
"""Доводить походження значення, простежуючи його писачів, а не назву поля.

Невідоме походження лишається невідомим. Об'єднання гілок зберігає кожне
можливе джерело; допис коду до її слів утворює інший вид тексту.
Поле-розрізнювач (`if (р.хто === 'ші') … else …р.текст`) відбирає записи, які доходять до читача: запис, чий
розрізнювач заданий сталою іншою, ніж у гілці, читачеві не потрапляє; незнаний розрізнювач фільтр знімає (11823).
Порожній літерал тексту не несе, коли всі його доповнення видно: походження
дають писачі доданих елементів. Поле запису з `Object.assign` чи spread
пише останній аргумент, що його задає; поле, якого не задає жоден, — недоведене.
Цикл носіїв (змінна ↔ сховище через писача) — не писач: походження в ньому дають
писачі, що вносять значення ззовні, а зворотне ребро нічого не додає; передача
значення в писача сховища з ключем — носій, а не втеча. Сталий напис чи число коду,
записані в поле, яке пише й вона, — не свій текст для читача поля (рішення 31.10, 11787).
"""
import re

# Поле, якого немає в літералі запису. Усередині обходу воно відрізняє «аргумент поля
# не задає» від невідомого значення; назовні (`походження`) це недоведений писач.
НЕМАЄ = 'немає'

# Зворотне ребро циклу: позначка кадру, до якого веде ребро. Кадр-голова її знімає —
# ребро нічого не додає до того, що в цикл вносять писачі ззовні.
ЦИКЛ = 'цикл#'

# Порожній рядок (`''`, порожній шаблон) — сталий, але без тексту: напису в поле не вносить.
# Назовні (`походження`) він — «стале», як і раніше.
ПОРОЖНЄ = 'порожнє'

# `null`/`undefined` — значення без тексту й без числа: напису в поле не вносять.
# Назовні — «число», як і раніше.
ПУСТЕ = 'пусте'

# Сталий напис чи число коду, записані в поле, яке пише й вона: читач поля не відрізнить
# їх від її слів інакше, ніж за словами, тож це не свій текст (рішення 31.10, 11787).
НАПИС = 'напис коду'


class Фільтр(str):
    """Умова розрізнювача на запис у шляху полів: `поле` дорівнює (`=`) чи не дорівнює (`≠`) сталій `зн` (11823).

    `оп == 'масив'` — значення в гілці `Array.isArray(E) ? … : …` є масивом: літерал запису, `null` чи поле, якого
    немає, туди не доходять.

    Стоїть у шляху на місці запису, до полів якого йде читання; записом, якого умова не пропускає, читач не
    дістає нічого. Умову від поля-рядка відрізняє тип, а не текст.
    """
    def __new__(кл, поле, оп, зн=''):
        ф = str.__new__(кл, '?%s%s%s' % (поле, оп, зн))
        ф.поле, ф.оп, ф.зн = поле, оп, зн
        return ф


def без_фільтрів(поля):
    """Шлях полів без умов розрізнювача — для звірки з писачами полів, які умови не знають."""
    return tuple(п for п in поля if not isinstance(п, Фільтр))


# Скільки разів вузол може стояти в обході з іншими полями чи контекстом: функція, до якої цикл носіїв доходить двома
# викликами (`ЧАТ_П.map(f)` і `з.чат.map(f)`), — не рекурсія без кінця; третій повтор — невідоме (межа обходу, 11823).
ПОВТОРИ_ВУЗЛА = 2

СТАЛІ = frozenset({'стале', 'число', ПОРОЖНЄ, ПУСТЕ})

# Подія вводу в поле: її `target` — саме поле (у поля вводу нема дочірніх вузлів), `currentTarget` — вузол обробника.
ПОДІЇ_ВВОДУ = frozenset({'input', 'change'})

# Клас розпізнавання мовлення браузера: результат його події `result` — її слова голосом (клас паспорта).
КЛАСИ_МОВЛЕННЯ = frozenset({'SpeechRecognition', 'webkitSpeechRecognition'})


def пробіли(ток):
    """Сталий рядок чи регулярний вираз лише з пробільних знаків: слів не вносить і не прибирає."""
    вид, зн = ток[0], ток[1]
    if вид == 'str':
        return not зн.strip()
    if вид == 're':
        тіло = зн[1:зн.rfind('/')]
        return not re.sub(r'\\s|[ ^$+*?]', '', тіло)
    return False


def чисте(дж):
    """Джерела без позначок зворотних ребер."""
    return {д for д in дж if not д.startswith(ЦИКЛ)}


def назовні(дж):
    """Джерела для виводу: порожній рядок — «стале», як до розрізнення; зворотне ребро в доказі — «цикл»."""
    вих = чисте(дж)
    if ПОРОЖНЄ in вих:
        вих = (вих - {ПОРОЖНЄ}) | {'стале'}
    if ПУСТЕ in вих:
        вих = (вих - {ПУСТЕ}) | {'число'}
    if any(д.startswith(ЦИКЛ) for д in дж):
        вих |= {'цикл'}
    return вих


class Походження:
    """Зворотний обхід виразів, присвоєнь, параметрів і повернень."""

    def __init__(с, програма, розділити, входи):
        """Приймає лексичну модель та виведені з модуля входи екрана."""
        с.п, с.розділити, с.входи = програма, розділити, входи
        с.кеш, с.стек = {}, {}
        с.кадри, с.низ = {}, []
        с.контекст, с.контексти, с.номери = 0, [{}], {(): 0}
        с.докази, с.сліди = set(), {}
        с.писачі = None
        с.поля_каталогу = None
        с.втечі = {}
        с.носії_значень = None
        с.псевдоніми = None
        с.читаються = {}
        с.мапи = {}
        с.охорони = {}
        с.масиви = {}
        с.незмінні = {}

    def походження(с, м, а, б):
        """Доведені джерела значення; поле, якого не задав жоден писач запису, — невідоме."""
        дж = назовні(с.вираз(м, а, б))
        return (дж - {НЕМАЄ}) | {'невідоме'} if НЕМАЄ in дж else дж

    def останній_писач(с, м, частини, поля, обчислене=False):
        """Поле запису з кількох частин: від останньої до першої, доки частина поле напевно не задасть.

        Частина — `(х, у, поля частини, ключ)` або `None` для чужого ключа, що поля не задає.
        Ключ поля задає його завжди, хай і значенням без поля (тоді воно невідоме). Аргумент
        `Object.assign` чи spread з полем, якого немає, з невідомим значенням чи без значення
        поля напевно не задає: тоді важать і ранніші. Не задав ніхто — поля немає; обчислений
        ключ (`[к]: …`) міг його задати — невідоме. Умова на значенні поля, якого немає (`Array.isArray(з.чат)`,
        розрізнювач запису), не справджується — тексту воно не дає (11823).
        """
        дж = set()
        for частина in reversed(частини):
            if частина is None:
                continue
            х, у, свої, ключ = частина
            вих = с.вираз(м, х, у, свої)
            if ключ:
                return дж | (вих - {НЕМАЄ}) | ({'невідоме'} if НЕМАЄ in вих else set())
            дж |= вих - {НЕМАЄ}
            if чисте(вих) and not вих & {НЕМАЄ, 'невідоме'}:
                return дж
        if обчислене:
            return дж | {'невідоме'}
        return дж if поля[1:2] and isinstance(поля[1], Фільтр) else дж | {НЕМАЄ}

    def без_доповнень(с, м, а, б):
        """Чи всі доповнення порожнього літерала видно обходові.

        Так — для запасного значення (`x || []`) і для значення змінної, яку код лише читає
        полями, переписує чи доповнює через `push`/`x[і] =` (ці записи обхід бачить сам).
        Змінна, передана далі (аргумент, інше присвоєння, повернення), може дістати елементи
        повз обхід — тоді літерал лишається невідомим.
        """
        т = м.ток
        if а > 0 and т[а - 1][1] in ('||', '??', '?'):
            return True
        if а > 0 and т[а - 1][1] == ',':
            return с.значення_мапи(м, а, б)
        if а > 0 and т[а - 1][1] == ':':
            # Гілка `умова ? x : []` — те саме запасне значення; ключ запису (`{к: []}`) — ні.
            і = а - 2
            while і >= 0 and not (т[і][0] == 'p' and т[і][1] in ('(', '[', '{', ',', ';', '?')):
                і = (м.пар[і] if т[і][0] == 'p' and т[і][1] in (')', ']', '}') and і in м.пар else і) - 1
            if і >= 0 and т[і][1] == '?':
                return True
            return с.без_доповнень_поля(м, а, б)
        if not (а >= 2 and т[а - 1][1] == '=' and т[а - 2][0] == 'id'
                and (а < 3 or т[а - 3][1] not in ('.', '?.')) and м.кінець_виразу(а) == б):
            return False
        return not с.втеча(м.ключ(а - 2, т[а - 2][1]))

    def втеча(с, ключ):
        """Чи змінну передають далі (аргумент, інше присвоєння, повернення), де її можуть доповнити повз обхід.

        Читання полями, перезапис, доповнення, порівняння, оголошення (зокрема ім'я в шаблоні) й обхід `for…of` — не
        втеча; значення писача сховища з ключем — носій, а не втеча. Гілка `||`/`??`/`?:` — те саме значення, що й
        увесь вираз; повернення — втеча, лише коли тікає результат якогось виклику функції; аргумент — коли тікає
        параметр функції-цілі (11823). Змінна, чию втечу ще судять (взаємні виклики), — втеча.
        """
        if ключ not in с.втечі:
            с.втечі[ключ] = True
            ім, втеча = ключ[1], False
            ф = с.п.ф_за_ід.get(ключ[0])
            for м2 in с.п.модулі:
                т2 = м2.ток
                for і, (вид, зн, _) in enumerate(т2):
                    if вид != 'id' or зн != ім or (і and т2[і - 1][1] in ('.', '?.')) or м2.ключ(і, ім) != ключ:
                        continue
                    if ф is not None and ф.мод is м2 and ф.заг_а <= і < ф.а and any(ім in и for _, и in ф.парам):
                        continue                                    # оголошення параметра
                    if с.у_шаблоні(м2, і) or (і and т2[і - 1][1] in ('const', 'let', 'var')):
                        continue
                    if с.втеча_місця(м2, і, і + 1):
                        втеча = True
                        break
                if втеча:
                    break
            с.втечі[ключ] = втеча
        return с.втечі[ключ]

    def втеча_місця(с, м, а, б, глибина=0):
        """Чи значення виразу (а, б) може дістатись коду, якого обхід не бачить (див. `втеча`)."""
        т, пар = м.ток, м.пар
        if глибина > 20:
            return True
        далі = т[б][1] if б < len(т) else ''
        перед = т[а - 1][1] if а else ''
        if далі in ('.', '?.', '[', '=', '+=', '||=', '??=', '&&=', '===', '!==', '==', '!=') or \
                перед in ('!', 'typeof', 'of'):
            return False
        if (м.шлях, а, б) in с.значення_писачів():
            # Значення писача сховища з ключем: носій, читачів якого судять за писачем.
            return False
        if перед in ('||', '??', '?', ':') or далі in ('||', '??', ':'):
            # Гілка логічного чи умовного виразу: тікає, коли тікає весь вираз.
            о = а - 1
            while о >= 0:
                if т[о][1] in (')', ']', '}') and о in пар:
                    о = пар[о] - 1
                    continue
                if т[о][1] in ('(', '[', '{', ';', '=>', 'return', '=', ','):
                    break
                о -= 1
            if о >= 0 and т[о][1] == '(' and о in пар and not (о and (т[о - 1][0] == 'id' and
                                                                   т[о - 1][1] not in ('return', 'typeof') or
                                                                   т[о - 1][1] in (')', ']'))):
                return с.втеча_місця(м, о, пар[о] + 1, глибина + 1)
            if о >= 0 and т[о][1] in ('=>', 'return'):
                кінець = м.кінець_виразу(о + 1)
                if кінець >= б:
                    return с.втеча_місця(м, о + 1, кінець, глибина + 1)
            return True
        if перед in ('=>', 'return'):
            return с.втеча_повернення(м, а, б, глибина)
        if перед in ('(', ',') and далі in (',', ')'):
            return с.втеча_аргументу(м, а, б, глибина)
        return True

    def втеча_повернення(с, м, а, б, глибина):
        """Повернене функцією значення тікає, коли тікає результат якогось її виклику чи саму функцію передають далі."""
        т, пар = м.ток, м.пар
        ф = м.охоплює(а)
        if ф is None or not ф.ім:
            return True
        if т[а - 1][1] == '=>' and not (ф.вираз and ф.а == а and м.кінець_виразу(а) == б):
            return True
        if т[а - 1][1] == 'return' and (б >= len(т) or т[б][1] not in (';', '}')):
            return True
        for м2 in с.п.модулі:
            т2 = м2.ток
            for і, (вид, зн, _) in enumerate(т2):
                if вид != 'id' or зн != ф.ім or (і and т2[і - 1][1] in ('.', '?.', 'const', 'let', 'var', 'function')):
                    continue
                if і + 1 < len(т2) and т2[і + 1][1] == '(' and і + 1 in м2.пар:
                    if ф not in с.п.цілі(м2, і, зн):
                        continue
                    if с.втеча_місця(м2, і, м2.пар[і + 1] + 1, глибина + 1):
                        return True
                elif not (і + 1 < len(т2) and т2[і + 1][1] in (':',) and і and т2[і - 1][1] in ('{', ',')):
                    return True                                     # функцію передають далі
        return False

    def втеча_аргументу(с, м, а, б, глибина):
        """Аргумент виклику тікає, коли тікає параметр кожної функції-цілі; невідома ціль чи метод — втеча."""
        т, пар = м.ток, м.пар
        о = а - 1
        while о >= 0 and т[о][1] != '(':
            if т[о][1] in (')', ']', '}') and о in пар:
                о = пар[о] - 1
                continue
            if т[о][1] in ('[', '{', ';'):
                return True
            о -= 1
        if о < 1 or о not in пар or т[о - 1][0] != 'id' or (о >= 2 and т[о - 2][1] in ('.', '?.')):
            return True
        арг = с.розділити(т, пар, о + 1, пар[о])
        if (а, б) not in арг:
            return True
        к = арг.index((а, б))
        цілі = с.п.цілі(м, о - 1, т[о - 1][1]) if т[о - 1][1] in с.п.за_ім else []
        if not цілі:
            return True
        for ф in цілі:
            if к >= len(ф.парам) or len(ф.парам[к][1]) != 1 or ф.парам[к][0] != ф.парам[к][1][0]:
                return True
            if с.втеча((ф.ід, ф.парам[к][1][0])):
                return True
        return False

    @staticmethod
    def у_шаблоні(м, і):
        """Чи токен — ім'я в шаблоні деструктуризації оголошення (`const [a, b] = …`, `for (const {a} of …)`)."""
        т, пар = м.ток, м.пар
        о = і - 1
        while о >= 0:
            if т[о][1] in (')', ']', '}') and о in пар:
                о = пар[о] - 1
                continue
            if т[о][1] in ('[', '{'):
                if о and т[о - 1][1] in ('const', 'let', 'var'):
                    return True
                о -= 1
                continue
            if т[о][1] in (',', ':', '=') or т[о][0] == 'id':
                о -= 1
                continue
            return False
        return False

    def мапа(с, ключ):
        """Чи змінна — `Map`: кожен її писач — `new Map()` без початкових записів (11786)."""
        if ключ not in с.мапи:
            записи = [(м, х, у) for м, вид, (х, у), _ in с.п.присв.get(ключ, ()) if вид == '=']
            с.мапи[ключ] = bool(записи) and all(
                у - х == 4 and [т[1] for т in м.ток[х:у]] == ['new', 'Map', '(', ')'] for м, х, у in записи)
        return с.мапи[ключ]

    def значення_мапи(с, м, а, б):
        """Порожній літерал — значення запису `X.set(к, [])` у `Map` `X`: доповнення видно, коли `X` не передають далі,
        а значення дістають лише ланцюгом `X.get(к).…` чи обходом `for (const [к, v] of X)`, де `v` теж не передають
        (11786). Інший доступ до значень (`X.get(к)` окремо, `forEach`, `values`) — літерал лишається невідомим.
        """
        т, пар = м.ток, м.пар
        о = а - 1
        while о >= 0 and not (т[о][1] == '(' and пар.get(о, -1) >= б):
            о = пар[о] - 1 if т[о][1] in (')', ']', '}') and о in пар else о - 1
        if о < 3 or т[о - 1][1] != 'set' or т[о - 2][1] not in ('.', '?.') or т[о - 3][0] != 'id' or \
                (о > 3 and т[о - 4][1] in ('.', '?.')):
            return False
        арг = с.розділити(т, пар, о + 1, пар[о])
        if len(арг) != 2 or арг[1] != (а, б):
            return False
        ключ = м.ключ(о - 3, т[о - 3][1])
        if not с.мапа(ключ) or с.втеча(ключ):
            return False
        ім = ключ[1]
        for м2 in с.п.модулі:
            т2, п2 = м2.ток, м2.пар
            for і, (вид, зн, _) in enumerate(т2):
                if вид != 'id' or зн != ім or (і and т2[і - 1][1] in ('.', '?.')) or м2.ключ(і, ім) != ключ:
                    continue
                if і + 2 < len(т2) and т2[і + 1][1] in ('.', '?.'):
                    метод = т2[і + 2][1]
                    if метод == 'get':
                        if not (і + 3 in п2 and п2[і + 3] + 1 < len(т2) and т2[п2[і + 3] + 1][1] in ('.', '?.', '[')):
                            return False
                    elif метод not in ('set', 'has', 'size', 'delete', 'clear'):
                        return False
        for ключ_v, префікс in с.псевдонім(ключ):
            if префікс[:1] == ('*',) and префікс[1:2] in ((), ('#1',)) and с.втеча(ключ_v):
                return False
        return True

    def без_доповнень_поля(с, м, а, б):
        """Порожній літерал під ключем `K` запису `H = {…, K: []}`: доповнення видно, коли поле `K` змінюють
        лише через `H` чи його псевдоніми (`v = H`, `v = H.поле`), а передають далі хіба що в `JSON.stringify` (11780).

        Зміна поля `K` через інший вираз (копію, параметр), передача поля чи `[K]` у дужках — можлива невидима
        добавка: літерал лишається невідомим. Ім'я поля тут лише звужує пошук, доказ — збіг тримача.
        """
        т, пар = м.ток, м.пар
        if а < 2 or т[а - 2][0] not in ('id', 'str') or (а > 2 and т[а - 3][1] not in ('{', ',')):
            return False
        поле, о = str(т[а - 2][1]), а - 3
        while о >= 0 and not (т[о][1] == '{' and пар.get(о, -1) >= б):
            о = пар[о] - 1 if т[о][1] in (')', ']', '}') and о in пар else о - 1
            if о >= 0 and т[о][1] in ('(', '[') and пар.get(о, -1) >= б:
                return False
        if о < 2 or т[о - 1][1] != '=' or м.кінець_виразу(о) != пар[о] + 1:
            return False
        h = о - 2
        while h >= 2 and т[h][0] == 'id' and т[h - 1][1] == '.' and т[h - 2][0] == 'id':
            h -= 2
        if т[h][0] != 'id' or (h and т[h - 1][1] in ('.', '?.')):
            return False
        тримачі = {(м.ключ(h, т[h][1]), tuple(т[k][1] for k in range(h + 2, о - 1, 2)))}
        for ключ, шлях in list(тримачі):
            for (ключ_X, префікс), ключ_v in с.всі_псевдоніми():
                if ключ_X == ключ and шлях[:len(префікс)] == префікс:
                    тримачі.add((ключ_v, шлях[len(префікс):]))
        for м2 in с.п.модулі:
            т2, п2 = м2.ток, м2.пар
            for і, (вид, зн, _) in enumerate(т2):
                if вид == 'str' and зн == поле and і and т2[і - 1][1] == '[':
                    return False
                if вид != 'id' or зн != поле or not і or т2[і - 1][1] not in ('.', '?.'):
                    continue
                j = і - 2
                while j >= 2 and т2[j][0] == 'id' and т2[j - 1][1] in ('.', '?.') and т2[j - 2][0] == 'id':
                    j -= 2
                свій = т2[j][0] == 'id' and (м2.ключ(j, т2[j][1]), tuple(т2[k][1] for k in range(j + 2, і - 1, 2))) in тримачі
                далі = т2[і + 1][1] if і + 1 < len(т2) else ''
                зміна = далі == '=' or (далі in ('.', '?.') and і + 2 < len(т2) and т2[і + 2][1] in (
                    'push', 'unshift', 'splice', 'fill', 'copyWithin')) or (
                    далі == '[' and і + 1 in п2 and п2[і + 1] + 1 < len(т2) and т2[п2[і + 1] + 1][1] in ('=', '+=', '||=', '??='))
                if зміна and not свій:
                    return False
                if далі in (',', ')', ';', '}', ']', '') and not зміна and not с.у_серіалізації(м2, і):
                    return False
        return True

    def у_серіалізації(с, м, і):
        """Чи токен — усередині аргументу `JSON.stringify(…)`: серіалізація копіює, а не передає."""
        т = м.ток
        for о, з in м.пар.items():
            if т[о][1] == '(' and о < і < з and о >= 3 and т[о - 1][1] == 'stringify' and т[о - 3][1] == 'JSON':
                return True
        return False

    def всі_псевдоніми(с):
        """Пари ((ключ X, префікс), ключ v) для всіх псевдонімів: v вказує на X.префікс."""
        с.псевдонім(None)
        return [((ключ_X, префікс), ключ_v) for ключ_X, пари in с.псевдоніми.items() for ключ_v, префікс in пари]

    def значення_писачів(с):
        """Вирази, що йдуть у писача сховища з доведеним ключем: саме значення і аргументи обгорток до нього."""
        if с.носії_значень is None:
            if с.писачі is None:
                с.зібрати_писачів()
            с.носії_значень = set()
            for _, к, м, (а, б), контекст, _ in с.писачі:
                if not any(ч != '*' for ч in к):
                    continue
                бачені = set()
                while (м.шлях, а, б, контекст) not in бачені:
                    бачені.add((м.шлях, а, б, контекст))
                    с.носії_значень.add((м.шлях, а, б))
                    т = м.ток
                    if б - а >= 5 and т[а][1] == 'JSON' and т[а + 2][1] == 'stringify' and м.пар.get(а + 3) == б - 1:
                        # Серіалізація — той самий носій, як і в читанні (`JSON.parse`).
                        а, б = а + 4, б - 1
                        continue
                    if б - а != 1 or т[а][0] != 'id':
                        break
                    зв = с.контексти[контекст].get(м.ключ(а, м.ток[а][1]))
                    if not зв:
                        break
                    м, а, б, контекст = зв
        return с.носії_значень

    def псевдонім(с, ключ):
        """Змінні, що вказують на той самий запис чи його елемент: `v = X`, `X.find(…)`, `X[і]`, `for (v of X)`, `X.forEach(v => …)`.

        Запис поля псевдоніма (`v.назва = …`) — писач поля самого `X`; префікс — шлях від `X` до `v`.
        """
        if с.псевдоніми is None:
            с.псевдоніми = {}
            for ключ_v, записи in с.п.присв.items():
                for м, вид, (х, у), і in записи:
                    for ключ_X, префікс in с.ціль_псевдоніма(м, вид, х, у):
                        с.псевдоніми.setdefault(ключ_X, []).append((ключ_v, префікс + с.місце(м, вид, і, ключ_v)))
            for ф in с.п.ф_за_ід.values():
                if not ф.парам or ф.парам[0][0] == '*' or ф.заг_а < 2:
                    continue
                зв = с.п._зворотний(ф)
                метод = ф.мод.ток[ф.заг_а - 2][1]
                if isinstance(зв, tuple) and метод not in ('then', 'finally', 'reduce') and \
                        зв[1] - зв[0] == 1 and ф.мод.ток[зв[0]][0] == 'id':
                    х = зв[0]
                    с.псевдоніми.setdefault(ф.мод.ключ(х, ф.мод.ток[х][1]), []).append(
                        ((ф.ід, ф.парам[0][1][0]), ('*',)))
        return с.псевдоніми.get(ключ, ())

    @staticmethod
    def місце(м, вид, і, ключ):
        """Місце імені в шаблоні `for (const [a, b] of X)`: `('#k',)` для елемента ітерації; інакше без місця (11786)."""
        позиція = getattr(м, 'позиції', {}).get((і, ключ)) if вид == 'елемент' else None
        return () if позиція is None else ('#%d' % позиція,)

    def ціль_псевдоніма(с, м, вид, х, у, бачені=frozenset()):
        """Записи (ключ X, префікс), на які вказує значення `м[х:у]`: `X`, `X[і]`, `X.поле`, `X.find(…)`.

        Виклик `f(…)` — те саме, що повертає `f`, коли запис `X` живе довше за виклик (оголошений поза `f`):
        `в = відповідь(поз)` і `вх = відповідь(поз)` пишуть один запис `В[поз]`, тож писачі поля — через обидва (11861).
        Свіжий запис самої `f` у кожному виклику інший — не псевдонім.
        """
        т, пар = м.ток, м.пар
        while х < у and т[х][1] == 'await':
            х += 1
        while х < у and т[х][1] == '(' and пар.get(х) == у - 1:
            х, у = х + 1, у - 1
        if х >= у or т[х][0] != 'id':
            return []
        префікс = None
        if у - х == 1:
            префікс = () if вид == '=' else ('*',) if вид == 'елемент' else None
        elif вид == '=' and т[х + 1][1] == '[' and пар.get(х + 1) == у - 1:
            префікс = ('*',)
        elif вид == '=' and у - х >= 3 and (у - х) % 2 == 1 and all(
                т[k][1] in ('.', '?.') and т[k + 1][0] == 'id' for k in range(х + 1, у, 2)):
            # `v = X.поле` — псевдонім поля запису `X` (11780).
            префікс = tuple(т[k + 1][1] for k in range(х + 1, у, 2))
        elif вид == '=' and у - х >= 4 and т[х + 1][1] in ('.', '?.') and \
                т[х + 2][1] in ('find', 'findLast', 'at') and т[х + 3][1] == '(' and пар.get(х + 3) == у - 1:
            префікс = ('*',)
        elif вид == '=' and т[х + 1][1] == '(' and пар.get(х + 1) == у - 1 and (х == 0 or т[х - 1][1] not in ('.', '?.')):
            вих = []
            for ф in с.п.цілі(м, х, т[х][1]):
                if ф.ід in бачені:
                    continue
                мф = ф.мод
                повернення = [(ф.а, ф.б)] if ф.вираз else [
                    (і + 1, мф.кінець_виразу(і + 1)) for і in range(ф.а, ф.б)
                    if мф.ток[і][1] == 'return' and мф.охоплює(і) is ф]
                for х2, у2 in повернення:
                    for ключ_X, пр in с.ціль_псевдоніма(мф, '=', х2, у2, бачені | {ф.ід}):
                        g = с.п.ф_за_ід.get(ключ_X[0])
                        if g is None or not (ф.заг_а <= g.заг_а and g.б <= ф.б):
                            вих.append((ключ_X, пр))
            return вих
        return [] if префікс is None else [(м.ключ(х, т[х][1]), префікс)]

    def писачі_полів(с, ключ, поля, бачені=frozenset()):
        """Записи полів змінної (`x.f = …`, `push`, `Object.assign`) і полів її псевдонімів.

        Значення самого псевдоніма (`=`, елемент `for…of`) — його читання, а не запис у `X`.
        """
        вих = set()
        if ключ in бачені:
            return вих
        свій = not бачені
        бачені = бачені | {ключ}
        мапа = с.мапа(ключ) if ключ else False
        # Запис поля, шлях якого перетинає умову розрізнювача, її не знає: його звіряють і читають без умов (11823).
        чисті = без_фільтрів(поля)
        for м2, вид_запису, (х, у), і in с.п.присв.get(ключ, ()):
            if вид_запису == '=': continue
            if вид_запису == 'елемент':
                if свій:
                    вих.update(с.вираз(м2, х, у, ('*',) + с.місце(м2, вид_запису, і, ключ) + поля))
            elif чисті:
                т2 = м2.ток
                шлях, j = [], і + 1
                while j < len(т2):
                    if т2[j][1] in ('.', '?.') and j + 1 < len(т2):
                        if т2[j + 1][1] == 'get' and j + 2 in м2.пар and м2.пар[j + 2] < х:
                            # Значення запису `Map`: `X.get(к).…` — `('*', '#1')` (11786); іншого `X` запис не рахується.
                            if not мапа:
                                break
                            шлях += ['*', '#1']; j = м2.пар[j + 2] + 1
                            continue
                        шлях.append(т2[j + 1][1]); j += 2
                    elif т2[j][1] == '[' and j in м2.пар:
                        кінець = м2.пар[j]
                        шлях.append(т2[j + 1][1] if кінець == j + 2 and т2[j + 1][0] == 'str' else '*')
                        j = кінець + 1
                    else:
                        break
                if j < len(т2) and т2[j][1] == '(' and j in м2.пар and м2.пар[j] < х and шлях[-1:] == ['get']:
                    continue
                if мапа and шлях == ['set'] and j < len(т2) and т2[j][1] == '(' and j in м2.пар:
                    # `X.set(к, v)` у `Map`: запис — пара `[к, v]` (11786).
                    арг = с.розділити(т2, м2.пар, j + 1, м2.пар[j])
                    if (х, у) not in арг[:2]:
                        continue
                    шлях = ['*', '#%d' % арг.index((х, у))]
                if шлях and шлях[-1] in ('push', 'unshift'):
                    шлях[-1] = '*'
                if len(шлях) <= len(поля) and чисті[:len(шлях)] == поля[:len(шлях)] and all(
                        л == п or '*' in (л, п) for л, п in zip(шлях, поля)):
                    # Новий елемент (`push`) — запис, до якого умова розрізнювача стоїть саме за шляхом.
                    вих.update(с.вираз(м2, х, у, поля[len(шлях):]))
                elif len(шлях) <= len(чисті) and all(л == п or '*' in (л, п) for л, п in zip(шлях, чисті)):
                    вих.update(с.вираз(м2, х, у, чисті[len(шлях):]))
            else:
                вих.update(с.вираз(м2, х, у, чисті))
        for ключ_v, префікс in с.псевдонім(ключ):
            if len(префікс) <= len(поля) and all(л == п or '*' in (л, п) for л, п in zip(префікс, поля)) and \
                    чисті[:len(префікс)] == поля[:len(префікс)]:
                вих.update(с.писачі_полів(ключ_v, поля[len(префікс):], бачені))
            elif len(префікс) <= len(чисті) and all(л == п or '*' in (л, п) for л, п in zip(префікс, чисті)):
                вих.update(с.писачі_полів(ключ_v, чисті[len(префікс):], бачені))
            elif not поля:
                вих.update(с.писачі_полів(ключ_v, (), бачені))
        return вих

    def звязати(с, ф, м, арг, префікс=()):
        """Зв'язує параметри з аргументами одного виклику, зберігаючи їхні пари.

        `префікс` — шлях від аргументу до значення параметра: `('*',)` — елемент масиву для `X.map(f)` (11823).
        """
        предки, батько = set(), ф.мод.батько(ф)
        while батько:
            предки.add(батько.ід)
            батько = ф.мод.батько(батько)
        сер = {к: в for к, в in с.контексти[с.контекст].items() if к[0] in предки}
        for к, (_, імена) in enumerate(ф.парам):
            if к < len(арг):
                for ім in імена:
                    сер[(ф.ід, ім)] = (м, *арг[к], с.контекст) + ((префікс,) if префікс else ())
        ключ = tuple(sorted((repr(к), (в[0].шлях, *в[1:])) for к, в in сер.items()))
        if ключ not in с.номери:
            с.номери[ключ] = len(с.контексти)
            с.контексти.append(сер)
        return с.номери[ключ]

    def у_контексті(с, контекст, дія, *арг):
        """Обчислює вираз у контексті його писача або виклику."""
        попередній = с.контекст
        с.контекст = контекст
        try:
            return дія(*арг)
        finally:
            с.контекст = попередній

    def виклик(с, ф, м, арг, поля):
        """Простежує повернення з конкретними аргументами замість суміші всіх викликів."""
        return с.у_контексті(с.звязати(ф, м, арг), с.повернення, ф, поля)

    def розрізнювач(с, м, а, б, поле, верхній=False):
        """Що задає поле `поле` запису (а, б): `('так', х, у)` — значення, `('ні',)` — не задає, `('невідомо',)`.

        Літерал і `Object.assign` вирішує останній, хто задає поле; spread і незнане значення — невідомо. Верхній
        вираз, що лише передає запис далі (змінна, виклик, гілка, читання сховища), — `('прозорий',)`: умова йде з
        ним до його писачів. Поле, яке десь пишуть після створення запису, — невідомо (11823).
        """
        т, пар = м.ток, м.пар
        while а < б and т[а][1] in (';', 'await'):
            а += 1
        while а < б and т[а][1] == '(' and пар.get(а) == б - 1:
            а, б = а + 1, б - 1
        if not с.незмінне_поле(поле):
            return ('невідомо',)
        if а < б and т[а][1] == '{' and пар.get(а) == б - 1:
            for х, у in reversed(с.розділити(т, пар, а + 1, б - 1)):
                if т[х][1] in ('...', '['):
                    return ('невідомо',)
                if х + 1 < у and т[х + 1][1] == ':' and т[х][0] in ('id', 'str') and т[х][1] == поле:
                    return ('так', х + 2, у)
                if у - х == 1 and т[х][1] == поле:
                    return ('так', х, у)
            return ('ні',)
        if а < б and т[а][1] == '[' and пар.get(а) == б - 1:
            return ('невідомо',)
        if б - а >= 5 and [x[1] for x in т[а:а + 4]] == ['Object', '.', 'assign', '('] and пар.get(а + 3) == б - 1:
            for х, у in reversed(с.розділити(т, пар, а + 4, б - 1)):
                р = с.розрізнювач(м, х, у, поле)
                if р[0] != 'ні':
                    return р
            return ('ні',)
        питання = с.п._верх(т, пар, а, б, ('?',))
        if питання and not верхній:
            рівень, к = 1, питання[0] + 1
            while к < б:
                if т[к][0] == 'p' and т[к][1] in '([{' and к in пар:
                    к = пар[к] + 1
                    continue
                if т[к][1] == '?':
                    рівень += 1
                elif т[к][1] == ':':
                    рівень -= 1
                    if not рівень:
                        break
                к += 1
            гілки = [с.розрізнювач(м, питання[0] + 1, к, поле), с.розрізнювач(м, к + 1, б, поле)]
            return ('ні',) if all(г[0] == 'ні' for г in гілки) else ('невідомо',)
        return ('прозорий',) if верхній else ('невідомо',)

    def копія_запису(с, м, а, б, поле, наступне):
        """Літерал-копія `{хто: B.хто, текст: B.текст}`: позиція `B`, коли і розрізнювач, і читане поле взято з `B`.

        Тоді умова переходить на `B` (11823); інший вигляд — None, і умову знімають.
        """
        т, пар = м.ток, м.пар
        while а < б and т[а][1] == '(' and пар.get(а) == б - 1:
            а, б = а + 1, б - 1
        if not наступне or isinstance(наступне[0], Фільтр) or not (а < б and т[а][1] == '{' and пар.get(а) == б - 1):
            return None
        бази = {}
        for х, у in с.розділити(т, пар, а + 1, б - 1):
            if т[х][1] in ('...', '['):
                return None
            if т[х][1] in (поле, наступне[0]) and (у - х == 1 or т[х + 1][1] == ':'):
                if т[х][1] in бази or у - х != 5 or т[х + 2][0] != 'id' or т[х + 3][1] not in ('.', '?.') or \
                        т[х + 4][1] != т[х][1]:
                    return None
                бази[т[х][1]] = х + 2
        if len(бази) != 2:
            return None
        б1, б2 = бази[поле], бази[наступне[0]]
        if т[б1][1] != т[б2][1] or м.ключ(б1, т[б1][1]) != м.ключ(б2, т[б2][1]):
            return None
        return б1

    def незмінне_поле(с, поле):
        """Чи поле запису ніде не пишуть після створення (`x.поле =`, `x['поле'] =`, `delete`, `Object.assign` поверх).

        Запис через обчислений ключ (`x[к] =`) прилад полем не бачить — межа приладу, як і для інших полів (11823).
        """
        if поле not in с.незмінні:
            так = True
            ПРИСВОЄННЯ = ('=', '+=', '-=', '||=', '??=', '&&=', '++', '--')
            for м2 in с.п.модулі:
                т2, пар2 = м2.ток, м2.пар
                for і, (вид, зн, _) in enumerate(т2):
                    if зн == 'delete':
                        так = not any(т2[к][1] == поле for к in range(і + 1, min(і + 8, len(т2))))
                    elif зн == 'assign' and і >= 2 and т2[і - 2][1] == 'Object' and і + 1 in пар2:
                        for х, у in с.розділити(т2, пар2, і + 2, пар2[і + 1])[1:]:
                            if any(т2[к][1] == поле and т2[к - 1][1] not in ('.', '?.') for к in range(х, у)):
                                так = False
                    elif зн == поле and 0 < і and і + 1 < len(т2):
                        if т2[і - 1][1] in ('.', '?.') and т2[і + 1][1] in ПРИСВОЄННЯ:
                            так = False
                        elif вид == 'str' and т2[і - 1][1] == '[' and т2[і + 1][1] == ']' and і + 2 < len(т2) and \
                                т2[і + 2][1] in ПРИСВОЄННЯ:
                            так = False
                    if not так:
                        break
                if not так:
                    break
            с.незмінні[поле] = так
        return с.незмінні[поле]

    def масив_тут(с, м, а, б):
        """Чи вираз (а, б) стоїть у гілці `так` умови `Array.isArray(E) ? … : …` з тим самим `E` (ланцюг імен) (11823)."""
        т, пар = м.ток, м.пар
        if not (б - а == 1 and т[а][0] == 'id' or б - а >= 3 and т[б - 2][1] in ('.', '?.') and т[б - 1][0] == 'id'):
            return False
        ключ_місця = (м.шлях, а, б)
        if ключ_місця in с.масиви:
            return с.масиви[ключ_місця]
        вираз = [x[1] for x in т[а:б]]
        вих = False
        if all(x[0] == 'id' or x[1] in ('.', '?.') for x in т[а:б]):
            for і in range(max(а - 400, 0), а):
                if т[і][1] != 'isArray' or і < 2 or т[і - 1][1] != '.' or т[і - 2][1] != 'Array' or \
                        т[і + 1][1] != '(' or і + 1 not in пар:
                    continue
                з = пар[і + 1]
                if [x[1] for x in т[і + 2:з]] != вираз or м.ключ(і + 2, т[і + 2][1]) != м.ключ(а, т[а][1]) or \
                        з + 1 >= len(т) or т[з + 1][1] != '?':
                    continue
                рівень, к = 1, з + 2
                while к < len(т):
                    if т[к][0] == 'p' and т[к][1] in '([{' and к in пар:
                        к = пар[к] + 1
                        continue
                    if т[к][1] in (';', ')', ']', '}'):
                        break
                    if т[к][1] == '?':
                        рівень += 1
                    elif т[к][1] == ':':
                        рівень -= 1
                        if not рівень:
                            break
                    к += 1
                if к < len(т) and т[к][1] == ':' and з + 1 < а and б <= к:
                    вих = True
        с.масиви[ключ_місця] = вих
        return вих

    def охорона(с, м, а, ім):
        """Умова розрізнювача, під якою стоїть читання параметра `ім` у місці `а`: `if (ім.поле === 'зн') … else …`.

        Лише для параметра, якого функція не переписує; гілка `then` — умова як є, `else` — протилежна (11823).
        """
        ключ_місця = (м.шлях, а)
        if ключ_місця in с.охорони:
            return с.охорони[ключ_місця]
        вих = None
        ключ = м.ключ(а, ім)
        ф = с.п.ф_за_ід.get(ключ[0])
        if ф and ф.мод is м and any(ім in імена for _, імена in ф.парам) and \
                not any(вид == '=' for _, вид, _, _ in с.п.присв.get(ключ, ())):
            т, пар = м.ток, м.пар
            for і in range(max(ф.заг_а, 0), min(а, len(т) - 1)):
                if т[і][1] != 'if' or т[і + 1][1] != '(' or і + 1 not in пар:
                    continue
                з = пар[і + 1]
                умова = т[і + 2:з]
                if len(умова) != 5 or умова[0][1] != ім or умова[1][1] not in ('.', '?.') or умова[2][0] != 'id' or \
                        умова[3][1] not in ('===', '!==') or умова[4][0] != 'str' or м.ключ(і + 2, ім) != ключ:
                    continue
                тоді = (з + 1, с.кінець_інструкції(м, з + 1))
                інакше = None
                if тоді[1] is not None and тоді[1] + 1 < len(т) and т[тоді[1]][1] == 'else':
                    інакше = (тоді[1] + 1, с.кінець_інструкції(м, тоді[1] + 1))
                рівно = умова[3][1] == '==='
                if тоді[1] is not None and тоді[0] <= а < тоді[1]:
                    вих = Фільтр(умова[2][1], '=' if рівно else '≠', умова[4][1])
                elif інакше and інакше[1] is not None and інакше[0] <= а < інакше[1]:
                    вих = Фільтр(умова[2][1], '≠' if рівно else '=', умова[4][1])
        с.охорони[ключ_місця] = вих
        return вих

    @staticmethod
    def кінець_інструкції(м, а):
        """Кінець інструкції, що починається в `а` (блок `{…}` чи до `;`); складена (`if`, цикл, оголошення) — None."""
        т, пар = м.ток, м.пар
        if а >= len(т):
            return None
        if т[а][1] == '{':
            return пар[а] + 1 if а in пар else None
        if т[а][1] in ('if', 'for', 'while', 'do', 'switch', 'try', 'else', 'function', 'class', 'let', 'const', 'var'):
            return None
        і = а
        while і < len(т):
            if т[і][0] == 'p' and т[і][1] in '([{' and і in пар:
                і = пар[і] + 1
                continue
            if т[і][1] == ';':
                return і + 1
            if т[і][1] in (')', ']', '}'):
                return None
            і += 1
        return None

    def проєкція(с, м, а):
        """Контекст без зв'язків функцій, що не охоплюють місце `а`: значення виразу від них не залежить.

        Писач змінної в іншій функції обчислюється тим самим вузлом, звідки б до нього не прийшли, — повтор у циклі
        носіїв через виклик за ім'ям (`X.map(f)`) стає зворотним ребром, а не новим вузлом (11823).
        """
        if not с.контекст or '#' in м.шлях:
            return с.контекст
        сер = с.контексти[с.контекст]
        предки, ф = set(), м.охоплює(а)
        while ф:
            предки.add(ф.ід)
            ф = м.батько(ф)
        нове = {к: в for к, в in сер.items() if к[0] in предки}
        if len(нове) == len(сер):
            return с.контекст
        ключ = tuple(sorted((repr(к), (в[0].шлях, *в[1:])) for к, в in нове.items()))
        if ключ not in с.номери:
            с.номери[ключ] = len(с.контексти)
            с.контексти.append(нове)
        return с.номери[ключ]

    def вираз(с, м, а, б, поля=()):
        """Повертає всі доведені джерела.

        Повтор того самого виразу з тими самими полями й контекстом — зворотне ребро циклу
        носіїв: воно нічого не додає, походження дають писачі, що вносять значення в цикл
        ззовні (рішення 31.10, 11787); нема жодного — невідоме. Повтор з іншими полями чи
        контекстом типу не доводить. Значення, що залежить від незавершеного кадру, не кешується.
        """
        проєкція = с.проєкція(м, а)
        if проєкція != с.контекст:
            return с.у_контексті(проєкція, с.вираз, м, а, б, поля)
        ключ = (м.шлях, а, б, поля, с.контекст)
        if ключ in с.кеш:
            с.докази.update(с.сліди[ключ])
            return с.кеш[ключ]
        if ключ in с.кадри:
            глибина = с.кадри[ключ]
            с.низ[-1] = min(с.низ[-1], глибина)
            return frozenset({ЦИКЛ + str(глибина)})
        вузол = (м.шлях, а, б)
        if с.стек.get(вузол, 0) >= ПОВТОРИ_ВУЗЛА:
            return frozenset({'невідоме'})
        глибина = len(с.низ)
        с.стек[вузол] = с.стек.get(вузол, 0) + 1
        с.кадри[ключ] = глибина
        с.низ.append(глибина)
        попередні = с.докази
        с.докази = set()
        низ = глибина
        try:
            вих = frozenset(с._вираз(м, а, б, поля))
            низ = с.низ[-1]
            своє = ЦИКЛ + str(глибина)
            if своє in вих:
                вих = вих - {своє}
                if not вих:
                    вих = frozenset({'невідоме'})
            if низ >= глибина:
                с.кеш[ключ] = вих
                с.сліди[ключ] = set(с.докази)
            return вих
        finally:
            попередні.update(с.докази)
            с.докази = попередні
            с.стек[вузол] -= 1
            if not с.стек[вузол]:
                del с.стек[вузол]
            del с.кадри[ключ]
            с.низ.pop()
            if с.низ:
                с.низ[-1] = min(с.низ[-1], низ)

    def разом(с, м, частини, поля=()):
        """Об'єднує можливі значення гілок без ваг і порогів."""
        вих = set()
        for а, б in частини:
            вих.update(с.вираз(м, а, б, поля))
        return вих or {'невідоме'}

    def _вираз(с, м, а, б, поля):
        """Розбирає оператори й ланцюг доступу до значення."""
        т, пар = м.ток, м.пар
        while а < б and т[а][1] in (';', 'await', 'yield', '...'):
            а += 1
        if а >= б:
            return {'стале'}
        if поля and isinstance(поля[0], Фільтр) and поля[0].оп == 'масив':
            о = а
            while о < б and т[о][1] == '(' and пар.get(о) == б - 1:
                о, б = о + 1, б - 1
            if т[о][1] == '{' and пар.get(о) == б - 1 or б - о == 1 and (т[о][0] in ('str', 'num', 'tpl') or
                                                                       т[о][1] in ('null', 'undefined', 'true', 'false')):
                с.докази.add('%s:%d · гілка Array.isArray · не масив' % (м.шлях, м.рядок(а)))
                return set()
            if т[о][1] == '[' and пар.get(о) == б - 1 or б - о >= 4 and т[б - 1][1] == ')' and б - 1 in пар and \
                    т[пар[б - 1] - 1][1] in ('map', 'flatMap', 'filter', 'slice', 'concat') and \
                    т[пар[б - 1] - 2][1] in ('.', '?.'):
                return с.вираз(м, о, б, поля[1:])
            if not (б - о == 1 and т[о][0] == 'id' or т[о][1] == '(' or с.п._верх(т, пар, о, б, ('?', '||', '??', '&&')) or
                    б - о >= 3 and т[б - 2][1] in ('.', '?.') and т[б - 1][0] == 'id' or
                    т[б - 1][1] == ')' and б - 1 in пар and т[пар[б - 1] - 1][0] == 'id' and
                    т[пар[б - 1] - 1][1] in с.п.за_ім and т[пар[б - 1] - 2][1] not in ('.', '?.')):
                return с.вираз(м, о, б, поля[1:])
        elif not (поля and isinstance(поля[0], Фільтр)) and с.масив_тут(м, а, б):
            return с.вираз(м, а, б, (Фільтр('', 'масив'),) + поля)
        if поля and isinstance(поля[0], Фільтр) and поля[0].оп != 'масив':
            умова = поля[0]
            рішення = с.розрізнювач(м, а, б, умова.поле, True)
            if рішення[0] == 'прозорий':
                pass
            elif рішення[0] == 'так' and рішення[2] - рішення[1] == 1 and т[рішення[1]][0] == 'str':
                if (т[рішення[1]][1] == умова.зн) != (умова.оп == '='):
                    с.докази.add('%s:%d · розрізнювач · %s = %r не пропускає' % (
                        м.шлях, м.рядок(а), умова.поле, т[рішення[1]][1]))
                    return set()
                return с.вираз(м, а, б, поля[1:])
            elif рішення[0] == 'ні':
                # Поля нема — `undefined`: сталій не дорівнює.
                if умова.оп == '=':
                    return set()
                return с.вираз(м, а, б, поля[1:])
            else:
                копія = с.копія_запису(м, а, б, умова.поле, поля[1:2]) if рішення[0] == 'так' else None
                if копія is not None:
                    return с.вираз(м, копія, копія + 1, поля)
                return с.вираз(м, а, б, поля[1:])
        верх = lambda знаки: с.п._верх(т, пар, а, б, знаки)
        if верх(('=>',)) or т[а][1] in ('function', 'class'):
            return {'вузол'}
        питання = верх(('?',))
        if питання:
            рівень, к = 1, питання[0] + 1
            while к < б:
                if т[к][0] == 'p' and т[к][1] in '([{' and к in пар:
                    к = пар[к] + 1
                    continue
                if т[к][1] == '?':
                    рівень += 1
                elif т[к][1] == ':':
                    рівень -= 1
                    if not рівень:
                        break
                к += 1
            return с.разом(м, [(питання[0] + 1, к), (к + 1, б)], поля)
        for оператори in (('||', '??'), ('&&',)):
            позиції = верх(оператори)
            if позиції:
                межі = [а - 1] + позиції + [б]
                частини = [(межі[і] + 1, межі[і + 1]) for і in range(len(межі) - 1)]
                return с.разом(м, частини if оператори[0] != '&&' else частини[-1:], поля)
        if верх(('===', '==', '!==', '!=', '<', '>', '<=', '>=')):
            return {'число'}
        доданки = [і for і in верх(('+',)) if і > а and т[і - 1][1] not in ('(', ',', '=')]
        if доданки:
            межі = [а - 1] + доданки + [б]
            частини = [(межі[і] + 1, межі[і + 1]) for і in range(len(межі) - 1)]
            слова = [(х, у) for х, у in частини if not (у - х == 1 and пробіли(т[х]))]
            if слова:
                # Її слова, з'єднані лише пробілами (допис до її ж тексту), — її слова (11822).
                свої = с.разом(м, слова)
                if 'її' in свої and чисте(свої) <= {'її', ПОРОЖНЄ}:
                    с.докази.add('%s:%d · писач-жінка · її слова через пробіл' % (м.шлях, м.рядок(а)))
                    return свої
            дж = с.разом(м, частини)
            if 'її' in дж:
                дж = (дж - {'її'}) | {'складено'}
            elif not чисте(дж) <= СТАЛІ:
                дж |= {'складено'}
            с.докази.add('%s:%d · писач-продукт · складання додаванням' % (м.шлях, м.рядок(а)))
            return дж
        if верх(('-', '*', '/', '%', '**', '&', '|', '^', '<<', '>>')) or т[а][1] in ('!', '~', '-', '+', '++', '--'):
            return {'число'}
        # Від кінця ланцюга: поле передається писачеві об'єкта, а не
        # класифікується за власним ім'ям.
        if б - а >= 3 and т[б - 2][1] in ('.', '?.') and т[б - 1][0] == 'id':
            поле = т[б - 1][1]
            if поле in ('length', 'size'):
                return {'число'}
            if поле in ('childNodes', 'children', 'firstChild', 'lastChild'):
                return {'вузол'}
            if поле == 'value':
                база = с.вираз(м, а, б - 2)
                if база == {'елемент'}:
                    с.докази.add('%s:%d · писач-жінка · ввід .value' % (м.шлях, м.рядок(а)))
                    return {'її'}
            return с.вираз(м, а, б - 2, (поле,) + поля)
        if т[б - 1][1] == ']' and б - 1 in пар and пар[б - 1] > а:
            від = пар[б - 1]
            індекс = т[від + 1:б - 1]
            поле = індекс[0][1] if len(індекс) == 1 and індекс[0][0] == 'str' else '*'
            return с.вираз(м, а, від, (поле,) + поля)
        if т[а][1] == '(' and пар.get(а) == б - 1:
            return с.вираз(м, а + 1, б - 1, поля)
        if т[а][1] in ('{', '[') and пар.get(а) == б - 1:
            частини = с.розділити(т, пар, а + 1, б - 1)
            if not частини and с.без_доповнень(м, а, б):
                # Порожній літерал тексту не несе; додане — у писачах змінної.
                return set()
            if т[а][1] == '[':
                if поля and поля[0].startswith('#') and not any(т[х][1] == '...' for х, _ in частини):
                    # Елемент на місці `k` шаблону `[a, b]` (11786); нема його — `undefined`.
                    к = int(поля[0][1:])
                    return с.вираз(м, *частини[к], поля[1:]) if к < len(частини) else {ПУСТЕ}
                return с.разом(м, частини, поля[1:] if поля and поля[0] in ('*',) or поля[:1] and поля[0].startswith('#') else поля)
            if частини and поля and поля[0] != '*':
                # Поле запису пише останній, хто його задає (ключ чи spread); чужий ключ поля не задає.
                задачі, обчислене = [], False
                for х, у in частини:
                    if т[х][1] == '...':
                        задачі.append((х + 1, у, поля, False))
                    elif х + 1 < у and т[х + 1][1] == ':' and т[х][0] in ('id', 'str', 'num'):
                        задачі.append((х + 2, у, поля[1:], True) if str(т[х][1]) == поля[0] else None)
                    elif у - х == 1 and т[х][0] == 'id':
                        задачі.append((х, у, поля[1:], True) if т[х][1] == поля[0] else None)
                    else:
                        обчислене = True
                дж = с.останній_писач(м, задачі, поля, обчислене)
                if поля == ('назва',) and 'її' in дж and чисте(дж) <= СТАЛІ | {'її'}:
                    дж |= {'назва'}
                return дж
            значення = []
            for х, у in частини:
                if т[х][1] == '...':
                    значення.append((х + 1, у, поля))
                    continue
                if х + 1 < у and т[х + 1][1] == ':':
                    if not поля or поля[0] == '*' or т[х][1] == поля[0]:
                        значення.append((х + 2, у))
                elif у - х == 1 and (not поля or поля[0] == '*' or т[х][1] == поля[0]):
                    значення.append((х, у))
            дж = set()
            for частина in значення:
                х, у = частина[:2]
                дж.update(с.вираз(м, х, у, частина[2] if len(частина) == 3 else поля[1:] if поля else ()))
            if not дж and not значення and частини:
                дж = {'невідоме'}
            if not частини and поля:
                доповнюється = а >= 2 and т[а - 1][1] == '=' and т[а - 2][0] == 'id' and any(
                    вид == 'поле' for _, вид, _, _ in с.п.присв.get(м.ключ(а - 2, т[а - 2][1]), ()))
                if not доповнюється and not (а > 0 and т[а - 1][1] in ('||', '??')):
                    дж = set() if поля[1:2] and isinstance(поля[1], Фільтр) else {НЕМАЄ}
            # Назва тут має писача: поле об'єкта створене з її вводу.
            # Саме ім'я поля від fetch чи невідомого об'єкта нічого не доводить.
            if поля == ('назва',) and 'її' in дж and чисте(дж) <= СТАЛІ | {'її'}:
                дж |= {'назва'}
            return дж
        if т[б - 1][1] == ')' and б - 1 in пар:
            о = пар[б - 1]
            if о > а and т[о - 1][0] == 'id':
                ім = т[о - 1][1]
                арг = с.розділити(т, пар, о + 1, б - 1)
                if ім == 'Map' and о == а + 2 and т[а][1] == 'new' and not арг:
                    # Порожня `Map` тексту не несе, коли всі її записи видно (11786): походження — у писачах `set`.
                    return set() if с.без_доповнень(м, а, б) else {'невідоме'}
