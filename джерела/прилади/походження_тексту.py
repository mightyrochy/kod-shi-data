# -*- coding: utf-8 -*-
"""Доводить походження значення, простежуючи його писачів, а не назву поля.

Невідоме походження лишається невідомим. Об'єднання гілок зберігає кожне
можливе джерело; допис коду до її слів утворює інший вид тексту.
Порожній літерал тексту не несе, коли всі його доповнення видно: походження
дають писачі доданих елементів. Поле запису з `Object.assign` чи spread
пише останній аргумент, що його задає; поле, якого не задає жоден, — недоведене.
Цикл носіїв (змінна ↔ сховище через писача) — не писач: походження в ньому дають
писачі, що вносять значення ззовні, а зворотне ребро нічого не додає; передача
значення в писача сховища з ключем — носій, а не втеча. Сталий напис чи число коду,
записані в поле, яке пише й вона, — не свій текст для читача поля (рішення 31.10, 11787).
"""

# Поле, якого немає в літералі запису. Усередині обходу воно відрізняє «аргумент поля
# не задає» від невідомого значення; назовні (`походження`) це недоведений писач.
НЕМАЄ = 'немає'

# Зворотне ребро циклу: позначка кадру, до якого веде ребро. Кадр-голова її знімає —
# ребро нічого не додає до того, що в цикл вносять писачі ззовні.
ЦИКЛ = 'цикл#'

# Порожній рядок (`''`, порожній шаблон) — сталий, але без тексту: напису в поле не вносить.
# Назовні (`походження`) він — «стале», як і раніше.
ПОРОЖНЄ = 'порожнє'

# `null`/`undefined` — значення без тексту й без числа: напису в поле не вносять.
# Назовні — «число», як і раніше.
ПУСТЕ = 'пусте'

# Сталий напис чи число коду, записані в поле, яке пише й вона: читач поля не відрізнить
# їх від її слів інакше, ніж за словами, тож це не свій текст (рішення 31.10, 11787).
НАПИС = 'напис коду'

СТАЛІ = frozenset({'стале', 'число', ПОРОЖНЄ, ПУСТЕ})


def чисте(дж):
    """Джерела без позначок зворотних ребер."""
    return {д for д in дж if not д.startswith(ЦИКЛ)}


def назовні(дж):
    """Джерела для виводу: порожній рядок — «стале», як до розрізнення; зворотне ребро в доказі — «цикл»."""
    вих = чисте(дж)
    if ПОРОЖНЄ in вих:
        вих = (вих - {ПОРОЖНЄ}) | {'стале'}
    if ПУСТЕ in вих:
        вих = (вих - {ПУСТЕ}) | {'число'}
    if any(д.startswith(ЦИКЛ) for д in дж):
        вих |= {'цикл'}
    return вих


class Походження:
    """Зворотний обхід виразів, присвоєнь, параметрів і повернень."""

    def __init__(с, програма, розділити, входи):
        """Приймає лексичну модель та виведені з модуля входи екрана."""
        с.п, с.розділити, с.входи = програма, розділити, входи
        с.кеш, с.стек = {}, set()
        с.кадри, с.низ = {}, []
        с.контекст, с.контексти, с.номери = 0, [{}], {(): 0}
        с.докази, с.сліди = set(), {}
        с.писачі = None
        с.поля_каталогу = None
        с.втечі = {}
        с.носії_значень = None
        с.псевдоніми = None

    def походження(с, м, а, б):
        """Доведені джерела значення; поле, якого не задав жоден писач запису, — невідоме."""
        дж = назовні(с.вираз(м, а, б))
        return (дж - {НЕМАЄ}) | {'невідоме'} if НЕМАЄ in дж else дж

    def останній_писач(с, м, частини, поля, обчислене=False):
        """Поле запису з кількох частин: від останньої до першої, доки частина поле напевно не задасть.

        Частина — `(х, у, поля частини, ключ)` або `None` для чужого ключа, що поля не задає.
        Ключ поля задає його завжди, хай і значенням без поля (тоді воно невідоме). Аргумент
        `Object.assign` чи spread з полем, якого немає, з невідомим значенням чи без значення
        поля напевно не задає: тоді важать і ранніші. Не задав ніхто — поля немає; обчислений
        ключ (`[к]: …`) міг його задати — невідоме.
        """
        дж = set()
        for частина in reversed(частини):
            if частина is None:
                continue
            х, у, свої, ключ = частина
            вих = с.вираз(м, х, у, свої)
            if ключ:
                return дж | (вих - {НЕМАЄ}) | ({'невідоме'} if НЕМАЄ in вих else set())
            дж |= вих - {НЕМАЄ}
            if чисте(вих) and not вих & {НЕМАЄ, 'невідоме'}:
                return дж
        return дж | {'невідоме' if обчислене else НЕМАЄ}

    def без_доповнень(с, м, а, б):
        """Чи всі доповнення порожнього літерала видно обходові.

        Так — для запасного значення (`x || []`) і для значення змінної, яку код лише читає
        полями, переписує чи доповнює через `push`/`x[і] =` (ці записи обхід бачить сам).
        Змінна, передана далі (аргумент, інше присвоєння, повернення), може дістати елементи
        повз обхід — тоді літерал лишається невідомим.
        """
        т = м.ток
        if а > 0 and т[а - 1][1] in ('||', '??', '?'):
            return True
        if а > 0 and т[а - 1][1] == ':':
            # Гілка `умова ? x : []` — те саме запасне значення; ключ запису (`{к: []}`) — ні.
            і = а - 2
            while і >= 0 and not (т[і][0] == 'p' and т[і][1] in ('(', '[', '{', ',', ';', '?')):
                і = (м.пар[і] if т[і][0] == 'p' and т[і][1] in (')', ']', '}') and і in м.пар else і) - 1
            if і >= 0 and т[і][1] == '?':
                return True
        if not (а >= 2 and т[а - 1][1] == '=' and т[а - 2][0] == 'id'
                and (а < 3 or т[а - 3][1] not in ('.', '?.')) and м.кінець_виразу(а) == б):
            return False
        ім = т[а - 2][1]
        ключ = м.ключ(а - 2, ім)
        if ключ not in с.втечі:
            втеча = False
            for м2 in с.п.модулі:
                т2 = м2.ток
                for і, (вид, зн, _) in enumerate(т2):
                    if вид != 'id' or зн != ім or (і and т2[і - 1][1] in ('.', '?.')) or м2.ключ(і, ім) != ключ:
                        continue
                    далі = т2[і + 1][1] if і + 1 < len(т2) else ''
                    перед = т2[і - 1][1] if і else ''
                    if далі in ('.', '?.', '[', '=', '+=', '||=', '??=', '&&=', '===', '!==', '==', '!=') or \
                            перед in ('const', 'let', 'var', '!', 'typeof'):
                        continue
                    if (м2.шлях, і, і + 1) in с.значення_писачів():
                        # Значення писача сховища з ключем: носій, читачів якого судять за писачем.
                        continue
                    втеча = True
                    break
                if втеча:
                    break
            с.втечі[ключ] = втеча
        return not с.втечі[ключ]

    def значення_писачів(с):
        """Вирази, що йдуть у писача сховища з доведеним ключем: саме значення і аргументи обгорток до нього."""
        if с.носії_значень is None:
            if с.писачі is None:
                с.зібрати_писачів()
            с.носії_значень = set()
            for _, к, м, (а, б), контекст, _ in с.писачі:
                if not any(ч != '*' for ч in к):
                    continue
                бачені = set()
                while (м.шлях, а, б, контекст) not in бачені:
                    бачені.add((м.шлях, а, б, контекст))
                    с.носії_значень.add((м.шлях, а, б))
                    т = м.ток
                    if б - а >= 5 and т[а][1] == 'JSON' and т[а + 2][1] == 'stringify' and м.пар.get(а + 3) == б - 1:
                        # Серіалізація — той самий носій, як і в читанні (`JSON.parse`).
                        а, б = а + 4, б - 1
                        continue
                    if б - а != 1 or т[а][0] != 'id':
                        break
                    зв = с.контексти[контекст].get(м.ключ(а, м.ток[а][1]))
                    if not зв:
                        break
                    м, а, б, контекст = зв
        return с.носії_значень

    def псевдонім(с, ключ):
        """Змінні, що вказують на той самий запис чи його елемент: `v = X`, `X.find(…)`, `X[і]`, `for (v of X)`, `X.forEach(v => …)`.

        Запис поля псевдоніма (`v.назва = …`) — писач поля самого `X`; префікс — шлях від `X` до `v`.
        """
        if с.псевдоніми is None:
            с.псевдоніми = {}
            for ключ_v, записи in с.п.присв.items():
                for м, вид, (х, у), _ in записи:
                    т, пар = м.ток, м.пар
                    while х < у and т[х][1] == 'await':
                        х += 1
                    while х < у and т[х][1] == '(' and пар.get(х) == у - 1:
                        х, у = х + 1, у - 1
                    if х >= у or т[х][0] != 'id':
                        continue
                    префікс = None
                    if у - х == 1:
                        префікс = () if вид == '=' else ('*',) if вид == 'елемент' else None
                    elif вид == '=' and т[х + 1][1] == '[' and пар.get(х + 1) == у - 1:
                        префікс = ('*',)
                    elif вид == '=' and у - х >= 4 and т[х + 1][1] in ('.', '?.') and \
                            т[х + 2][1] in ('find', 'findLast', 'at') and т[х + 3][1] == '(' and пар.get(х + 3) == у - 1:
                        префікс = ('*',)
                    if префікс is not None:
                        с.псевдоніми.setdefault(м.ключ(х, т[х][1]), []).append((ключ_v, префікс))
            for ф in с.п.ф_за_ід.values():
                if not ф.парам or ф.парам[0][0] == '*' or ф.заг_а < 2:
                    continue
                зв = с.п._зворотний(ф)
                метод = ф.мод.ток[ф.заг_а - 2][1]
                if isinstance(зв, tuple) and метод not in ('then', 'finally', 'reduce') and \
                        зв[1] - зв[0] == 1 and ф.мод.ток[зв[0]][0] == 'id':
                    х = зв[0]
                    с.псевдоніми.setdefault(ф.мод.ключ(х, ф.мод.ток[х][1]), []).append(
                        ((ф.ід, ф.парам[0][1][0]), ('*',)))
        return с.псевдоніми.get(ключ, ())

    def писачі_полів(с, ключ, поля, бачені=frozenset()):
        """Записи полів змінної (`x.f = …`, `push`, `Object.assign`) і полів її псевдонімів.

        Значення самого псевдоніма (`=`, елемент `for…of`) — його читання, а не запис у `X`.
        """
        вих = set()
        if ключ in бачені:
            return вих
        свій = not бачені
        бачені = бачені | {ключ}
        for м2, вид_запису, (х, у), і in с.п.присв.get(ключ, ()):
            if вид_запису == '=': continue
            if вид_запису == 'елемент':
                if свій:
                    вих.update(с.вираз(м2, х, у, ('*',) + поля))
            elif поля:
                т2 = м2.ток
                шлях, j = [], і + 1
                while j < len(т2):
                    if т2[j][1] in ('.', '?.') and j + 1 < len(т2):
                        шлях.append(т2[j + 1][1]); j += 2
                    elif т2[j][1] == '[' and j in м2.пар:
                        кінець = м2.пар[j]
                        шлях.append(т2[j + 1][1] if кінець == j + 2 and т2[j + 1][0] == 'str' else '*')
                        j = кінець + 1
                    else:
                        break
                if шлях and шлях[-1] in ('push', 'unshift'):
                    шлях[-1] = '*'
                if len(шлях) <= len(поля) and all(л == п or '*' in (л, п) for л, п in zip(шлях, поля)):
                    вих.update(с.вираз(м2, х, у, поля[len(шлях):]))
            else:
                вих.update(с.вираз(м2, х, у, поля))
        for ключ_v, префікс in с.псевдонім(ключ):
            if len(префікс) <= len(поля) and all(л == п or '*' in (л, п) for л, п in zip(префікс, поля)):
                вих.update(с.писачі_полів(ключ_v, поля[len(префікс):], бачені))
            elif not поля:
                вих.update(с.писачі_полів(ключ_v, (), бачені))
        return вих

    def звязати(с, ф, м, арг):
        """Зв'язує параметри з аргументами одного виклику, зберігаючи їхні пари."""
        предки, батько = set(), ф.мод.батько(ф)
        while батько:
            предки.add(батько.ід)
            батько = ф.мод.батько(батько)
        сер = {к: в for к, в in с.контексти[с.контекст].items() if к[0] in предки}
        for к, (_, імена) in enumerate(ф.парам):
            if к < len(арг):
                for ім in імена:
                    сер[(ф.ід, ім)] = (м, *арг[к], с.контекст)
        ключ = tuple(sorted((repr(к), (в[0].шлях, *в[1:])) for к, в in сер.items()))
        if ключ not in с.номери:
            с.номери[ключ] = len(с.контексти)
            с.контексти.append(сер)
        return с.номери[ключ]

    def у_контексті(с, контекст, дія, *арг):
        """Обчислює вираз у контексті його писача або виклику."""
        попередній = с.контекст
        с.контекст = контекст
        try:
            return дія(*арг)
        finally:
            с.контекст = попередній

    def виклик(с, ф, м, арг, поля):
        """Простежує повернення з конкретними аргументами замість суміші всіх викликів."""
        return с.у_контексті(с.звязати(ф, м, арг), с.повернення, ф, поля)

    def вираз(с, м, а, б, поля=()):
        """Повертає всі доведені джерела.

        Повтор того самого виразу з тими самими полями й контекстом — зворотне ребро циклу
        носіїв: воно нічого не додає, походження дають писачі, що вносять значення в цикл
        ззовні (рішення 31.10, 11787); нема жодного — невідоме. Повтор з іншими полями чи
        контекстом типу не доводить. Значення, що залежить від незавершеного кадру, не кешується.
        """
        ключ = (м.шлях, а, б, поля, с.контекст)
        if ключ in с.кеш:
            с.докази.update(с.сліди[ключ])
            return с.кеш[ключ]
        if ключ in с.кадри:
            глибина = с.кадри[ключ]
            с.низ[-1] = min(с.низ[-1], глибина)
            return frozenset({ЦИКЛ + str(глибина)})
        вузол = (м.шлях, а, б)
        if вузол in с.стек:
            return frozenset({'невідоме'})
        глибина = len(с.низ)
        с.стек.add(вузол)
        с.кадри[ключ] = глибина
        с.низ.append(глибина)
        попередні = с.докази
        с.докази = set()
        низ = глибина
        try:
            вих = frozenset(с._вираз(м, а, б, поля))
            низ = с.низ[-1]
            своє = ЦИКЛ + str(глибина)
            if своє in вих:
                вих = вих - {своє}
                if not вих:
                    вих = frozenset({'невідоме'})
            if низ >= глибина:
                с.кеш[ключ] = вих
                с.сліди[ключ] = set(с.докази)
            return вих
        finally:
            попередні.update(с.докази)
            с.докази = попередні
            с.стек.remove(вузол)
            del с.кадри[ключ]
            с.низ.pop()
            if с.низ:
                с.низ[-1] = min(с.низ[-1], низ)

    def разом(с, м, частини, поля=()):
        """Об'єднує можливі значення гілок без ваг і порогів."""
        вих = set()
        for а, б in частини:
            вих.update(с.вираз(м, а, б, поля))
        return вих or {'невідоме'}

    def _вираз(с, м, а, б, поля):
        """Розбирає оператори й ланцюг доступу до значення."""
        т, пар = м.ток, м.пар
        while а < б and т[а][1] in (';', 'await', 'yield', '...'):
            а += 1
        if а >= б:
            return {'стале'}
        верх = lambda знаки: с.п._верх(т, пар, а, б, знаки)
        if верх(('=>',)) or т[а][1] in ('function', 'class'):
            return {'вузол'}
        питання = верх(('?',))
        if питання:
            рівень, к = 1, питання[0] + 1
            while к < б:
                if т[к][0] == 'p' and т[к][1] in '([{' and к in пар:
                    к = пар[к] + 1
                    continue
                if т[к][1] == '?':
                    рівень += 1
                elif т[к][1] == ':':
                    рівень -= 1
                    if not рівень:
                        break
                к += 1
            return с.разом(м, [(питання[0] + 1, к), (к + 1, б)], поля)
        for оператори in (('||', '??'), ('&&',)):
            позиції = верх(оператори)
            if позиції:
                межі = [а - 1] + позиції + [б]
                частини = [(межі[і] + 1, межі[і + 1]) for і in range(len(межі) - 1)]
                return с.разом(м, частини if оператори[0] != '&&' else частини[-1:], поля)
        if верх(('===', '==', '!==', '!=', '<', '>', '<=', '>=')):
            return {'число'}
        доданки = [і for і in верх(('+',)) if і > а and т[і - 1][1] not in ('(', ',', '=')]
        if доданки:
            межі = [а - 1] + доданки + [б]
            дж = с.разом(м, [(межі[і] + 1, межі[і + 1]) for і in range(len(межі) - 1)])
            if 'її' in дж:
                дж = (дж - {'її'}) | {'складено'}
            elif not чисте(дж) <= СТАЛІ:
                дж |= {'складено'}
            с.докази.add('%s:%d · писач-продукт · складання додаванням' % (м.шлях, м.рядок(а)))
            return дж
        if верх(('-', '*', '/', '%', '**', '&', '|', '^', '<<', '>>')) or т[а][1] in ('!', '~', '-', '+', '++', '--'):
            return {'число'}
        # Від кінця ланцюга: поле передається писачеві об'єкта, а не
        # класифікується за власним ім'ям.
        if б - а >= 3 and т[б - 2][1] in ('.', '?.') and т[б - 1][0] == 'id':
            поле = т[б - 1][1]
            if поле in ('length', 'size'):
                return {'число'}
            if поле in ('childNodes', 'children', 'firstChild', 'lastChild'):
                return {'вузол'}
            if поле == 'value':
                база = с.вираз(м, а, б - 2)
                if база == {'елемент'}:
                    с.докази.add('%s:%d · писач-жінка · ввід .value' % (м.шлях, м.рядок(а)))
                    return {'її'}
            return с.вираз(м, а, б - 2, (поле,) + поля)
        if т[б - 1][1] == ']' and б - 1 in пар and пар[б - 1] > а:
            від = пар[б - 1]
            індекс = т[від + 1:б - 1]
            поле = індекс[0][1] if len(індекс) == 1 and індекс[0][0] == 'str' else '*'
            return с.вираз(м, а, від, (поле,) + поля)
        if т[а][1] == '(' and пар.get(а) == б - 1:
            return с.вираз(м, а + 1, б - 1, поля)
        if т[а][1] in ('{', '[') and пар.get(а) == б - 1:
            частини = с.розділити(т, пар, а + 1, б - 1)
            if not частини and с.без_доповнень(м, а, б):
                # Порожній літерал тексту не несе; додане — у писачах змінної.
                return set()
            if т[а][1] == '[':
                return с.разом(м, частини, поля[1:] if поля and поля[0] == '*' else поля)
            if частини and поля and поля[0] != '*':
                # Поле запису пише останній, хто його задає (ключ чи spread); чужий ключ поля не задає.
                задачі, обчислене = [], False
                for х, у in частини:
                    if т[х][1] == '...':
                        задачі.append((х + 1, у, поля, False))
                    elif х + 1 < у and т[х + 1][1] == ':' and т[х][0] in ('id', 'str', 'num'):
                        задачі.append((х + 2, у, поля[1:], True) if str(т[х][1]) == поля[0] else None)
                    elif у - х == 1 and т[х][0] == 'id':
                        задачі.append((х, у, поля[1:], True) if т[х][1] == поля[0] else None)
                    else:
                        обчислене = True
                дж = с.останній_писач(м, задачі, поля, обчислене)
                if поля == ('назва',) and 'її' in дж and чисте(дж) <= СТАЛІ | {'її'}:
                    дж |= {'назва'}
                return дж
            значення = []
            for х, у in частини:
                if т[х][1] == '...':
                    значення.append((х + 1, у, поля))
                    continue
                if х + 1 < у and т[х + 1][1] == ':':
                    if not поля or поля[0] == '*' or т[х][1] == поля[0]:
                        значення.append((х + 2, у))
                elif у - х == 1 and (not поля or поля[0] == '*' or т[х][1] == поля[0]):
                    значення.append((х, у))
            дж = set()
            for частина in значення:
                х, у = частина[:2]
                дж.update(с.вираз(м, х, у, частина[2] if len(частина) == 3 else поля[1:] if поля else ()))
            if not дж and not значення and частини:
                дж = {'невідоме'}
            if not частини and поля:
                доповнюється = а >= 2 and т[а - 1][1] == '=' and т[а - 2][0] == 'id' and any(
                    вид == 'поле' for _, вид, _, _ in с.п.присв.get(м.ключ(а - 2, т[а - 2][1]), ()))
                if not доповнюється and not (а > 0 and т[а - 1][1] in ('||', '??')):
                    дж = {НЕМАЄ}
            # Назва тут має писача: поле об'єкта створене з її вводу.
            # Саме ім'я поля від fetch чи невідомого об'єкта нічого не доводить.
            if поля == ('назва',) and 'її' in дж and чисте(дж) <= СТАЛІ | {'її'}:
                дж |= {'назва'}
            return дж
        if т[б - 1][1] == ')' and б - 1 in пар:
            о = пар[б - 1]
            if о > а and т[о - 1][0] == 'id':
                ім = т[о - 1][1]
                арг = с.розділити(т, пар, о + 1, б - 1)
                if ім == 'Promise':
                    вих = set()
                    for ф in м.функції_в(о + 1, б - 1):
                        if not ф.парам or м.батько(ф) is not м.охоплює(а):
                            continue
                        рез = ф.парам[0][1]
                        for ім2, арг2, і2 in м.виклики:
                            if ім2 in рез and м.ключ(і2, ім2) == (ф.ід, ім2) and арг2:
                                вих.update(с.разом(м, арг2, поля))
                    return вих or {'невідоме'}
                if ім in ('Number', 'parseInt', 'parseFloat', 'Boolean', 'isNaN', 'isFinite', 'BigInt'):
                    return {'число'}
                if т[а][1] == 'Math':
                    return {'число'}
                if ім == 'fetch':
                    return с.каталог(м, арг, поля)
                if ім in ('postMessage', 'runPython', 'runPythonAsync', 'містП'):
                    с.докази.add('писач недоведений · %s:%d · %s · поле %s' % (
                        м.шлях, м.рядок(о - 1), ім, '.'.join(поля) or 'відповідь'))
                    с.кандидати_поля(поля)
                    return {'невідоме'}
                if ім in ('$', 'createElement', 'getElementById', 'querySelector'):
                    if поля and поля[0] == 'value':
                        # Читання поля вводу — джерело її слів; приховані ключі
                        # лишаються кодами, якщо тип елемента доведено розміткою.
                        відомі = getattr(с.п, 'елементи', {})
                        ід = т[арг[0][0]][1] if арг and т[арг[0][0]][0] == 'str' else None
                        тип = відомі.get(ід, ('', ''))
                        if тип[0].lower() in ('select', 'option') or 'hidden' in тип[1]:
                            return {'код'}
                        с.докази.add('%s:%d · писач-жінка · ввід %s' % (м.шлях, м.рядок(а), ід or '?'))
                        return {'її'} if len(поля) == 1 else {'невідоме'}
                    return {'елемент'} if not поля else {'невідоме'}
                if ім in с.входи:
                    # Повернений елемент уже має текст; append цього елемента
                    # не є другим записом того самого тексту.
                    функції = с.п.цілі(м, о - 1, ім)
                    результати = set().union(*(с.повернення(ф, ()) for ф in функції)) if функції else set()
                    if результати and результати <= {'елемент', 'вузол'}:
                        return результати
                    види = {вид for _, вид in с.входи[ім]}
                    if види <= {'проза', 'збій'}:
                        return {'перевірено'}
                    return с.разом(м, [арг[к] for к, _ in с.входи[ім] if к < len(арг)], поля)
                if ім in ('String', 'encodeURIComponent', 'decodeURIComponent'):
                    return с.разом(м, арг, поля)
                if о >= а + 3 and т[о - 2][1] in ('.', '?.'):
                    база = (а, о - 2)
                    носії = с.носій(м, *база) if ім in ('getItem', 'get', 'getAll') else set()
                    if ім in ('getItem', 'get', 'getAll') and носії:
                        ключі = {('*',)} if ім == 'getAll' else с.ключі(м, *арг[0]) if арг else set()
                        шлях = поля[1:] if поля[:1] == ('result',) else поля
                        if ім == 'getAll' and шлях[:1] == ('*',):
                            шлях = шлях[1:]
                        return с.читання(носії, ключі, шлях)
                    if ім == 'assign' and т[а][1] == 'Object':
                        if поля and поля[0] != '*' and арг:
                            return с.останній_писач(м, [(х, у, поля, False) for х, у in арг], поля)
                        return с.разом(м, арг, поля)
                    if ім == 'then' and арг:
                        вих = set()
                        for ф in м.функції_в(*арг[0]):
                            if м.батько(ф) is м.охоплює(а):
                                вих.update(с.повернення(ф, поля))
                        return вих or {'невідоме'}
                    if ім in ('toFixed', 'toPrecision', 'getTime', 'getFullYear', 'indexOf', 'findIndex', 'includes', 'has', 'test'):
                        return {'число'}
                    if ім in ('stringify', 'parse') and т[а][1] == 'JSON':
                        return с.разом(м, арг, поля)
                    if ім in ('trim', 'trimStart', 'trimEnd', 'toString', 'slice', 'substring', 'substr'):
                        return с.вираз(м, *база, поля)
                    if ім in ('replace', 'replaceAll', 'join', 'toLowerCase', 'toUpperCase', 'padStart', 'padEnd'):
                        дж = с.вираз(м, *база, поля)
                        if not чисте(дж) <= СТАЛІ:
                            с.докази.add('%s:%d · писач-продукт · %s' % (м.шлях, м.рядок(а), ім))
                            return (дж - {'її'}) | {'складено'}
                        return дж
                    if ім in ('filter', 'sort', 'reverse', 'find', 'at', 'pop', 'shift'):
                        return с.вираз(м, *база, (('*',) + поля) if ім in ('find', 'at', 'pop', 'shift') else поля)
                    if ім in ('map', 'flatMap') and арг:
                        вих = set()
                        for ф in м.функції_в(*арг[0]):
                            if м.батько(ф) is м.охоплює(а):
                                вих.update(с.повернення(ф, поля[1:] if поля[:1] == ('*',) else поля))
                        return вих or {'невідоме'}
                    if ім in ('json', 'text'):
                        return с.вираз(м, *база, поля)
                if ім in с.п.за_ім:
                    вих = set()
                    for ф in с.п.цілі(м, о - 1, ім):
                        вих.update(с.виклик(ф, м, арг, поля))
                    return вих or {'невідоме'}
                return {'невідоме'}
        if б - а == 1:
            вид, зн, _ = т[а]
            if зн in ('null', 'undefined'):
                return {ПУСТЕ}
            if вид == 'num' or зн in ('true', 'false'):
                return {'число'}
            if вид in ('str', 're'):
                return ({ПОРОЖНЄ} if вид == 'str' and зн == '' else {'стале'}) if not поля else {'невідоме'}
            if вид == 'tpl':
                # Вкладені вирази лексер зберігає окремим списком токенів.
                дж = set()
                for тип, значення in зн:
                    if тип == 's' and значення:
                        дж.add('стале')
                    elif тип == 'e':
                        вкладений = type(м)(м.шлях + '#шаблон' + str(а), значення)
                        вкладений.ключ = lambda і, ім: м.ключ(а, ім)
                        дж.update(с.вираз(вкладений, 0, len(значення)))
                if 'її' in дж and len(зн) > 1:
                    дж = (дж - {'її'}) | {'складено'}
                elif len(зн) > 1 and not чисте(дж) <= СТАЛІ:
                    дж |= {'складено'}
                return дж or {ПОРОЖНЄ if not зн else 'стале'}
            if вид == 'id':
                if зн in с.п.закріплені:
                    return {'стале'}
                ключ = м.ключ(а, зн)
                звязаний = с.контексти[с.контекст].get(ключ)
                if звязаний:
                    м2, х, у, контекст = звязаний
                    return с.у_контексті(контекст, с.вираз, м2, х, у, поля)
                вих = set()
                записи = с.п.присв.get(ключ, ())
                for м2, вид_запису, (х, у), _ in записи:
                    if вид_запису != '=': continue
                    вих.update(с.вираз(м2, х, у, поля))
                if not поля and чисте(вих) and чисте(вих) <= {'елемент', 'вузол'}:
                    return вих
                вих.update(с.писачі_полів(ключ, поля))
                ф = с.п.ф_за_ід.get(ключ[0])
                if ф:
                    for к, (_, імена) in enumerate(ф.парам):
                        if зн not in імена:
                            continue
                        for м2, арг, _ in с.п.виклики.get(ф.ід, ()):
                            if к < len(арг):
                                вих.update(с.вираз(м2, *арг[к], поля))
                        зв = с.п._зворотний(ф)
                        if к == 0 and isinstance(зв, tuple):
                            # then отримує результат, а не елемент масиву.
                            метод = ф.мод.ток[ф.заг_а - 2][1] if ф.заг_а >= 2 else ''
                            вих.update(с.вираз(ф.мод, *зв, поля if метод == 'then' else ('*',) + поля))
                if поля and 'її' in вих and вих & {'стале', 'число'}:
                    # Сталий напис чи число коду в полі, яке пише й вона: не свій текст для читача поля.
                    вих.add(НАПИС)
                return вих or {'невідоме'}
        return {'невідоме'}

    def повернення(с, ф, поля):
        """Простежує всі повернення функції до їхніх джерел."""
        м = ф.мод
        if ф.вираз:
            return с.вираз(м, ф.а, ф.б, поля)
        частини = [(і + 1, м.кінець_виразу(і + 1)) for і in range(ф.а, ф.б)
                   if м.ток[і][1] == 'return' and м.охоплює(і) is ф]
        return с.разом(м, частини, поля)

    def контексти_місця(с, м, і, бачені=frozenset()):
        """Розгортає виклики обгортки писача зі зв'язаними ключем і значенням."""
        ф = м.охоплює(і)
        while ф and (not ф.ім or not с.п.виклики.get(ф.ід)) and м.батько(ф):
            ф = м.батько(ф)
        if not ф or not ф.парам or ф.ід in бачені:
            return [с.контекст]
        виклики = с.п.виклики.get(ф.ід, ())
        вих = []
        for м2, арг, і2 in виклики:
            область = м2.охоплює(і2)
            while область and область is not ф:
                область = м2.батько(область)
            if область is ф and len(арг) == len(ф.парам) and all(
                    у - х == 1 and м2.ток[х][1] == ім
                    for (х, у), (ім, _) in zip(арг, ф.парам)):
                # Повтор того самого виклику не створює нового писача ключа.
                continue
            for контекст in с.контексти_місця(м2, і2, бачені | {ф.ід}):
                вих.append(с.у_контексті(контекст, с.звязати, ф, м2, арг))
        return вих or [с.контекст]

    def ключі(с, м, а, б, бачені=frozenset()):
        """Виводить літеральні частини ключа; невідома частина лишається зірочкою."""
        т, пар = м.ток, м.пар
        вузол = (м.шлях, а, б, с.контекст)
        if вузол in бачені:
            return set()
        if а >= б:
            return {('*',)}
        бачені = бачені | {вузол}
        while а < б and т[а][1] in ('await', 'new'):
            а += 1
        if т[а][1] == '(' and пар.get(а) == б - 1:
            return с.ключі(м, а + 1, б - 1, бачені)
        доданки = с.п._верх(т, пар, а, б, ('+',))
        if доданки:
            вих, межі = {()}, [а - 1] + доданки + [б]
            for х, у in zip(межі, межі[1:]):
                вих = {ліва + права for ліва in вих for права in с.ключі(м, х + 1, у, бачені)}
            return {с.стиснути_ключ(к) for к in вих}
        if б - а == 1:
            if т[а][0] in ('str', 'num'):
                return {(str(т[а][1]),)}
            if т[а][0] == 'id':
                ключ = м.ключ(а, т[а][1])
                зв = с.контексти[с.контекст].get(ключ)
                if зв:
                    м2, х, у, контекст = зв
                    return с.у_контексті(контекст, с.ключі, м2, х, у, бачені)
                вих = set()
                for м2, вид, (х, у), _ in с.п.присв.get(ключ, ()):
                    if вид == '=':
                        вих.update(с.ключі(м2, х, у, бачені))
                ф = с.п.ф_за_ід.get(ключ[0])
                if ф:
                    for к, (_, імена) in enumerate(ф.парам):
                        if т[а][1] in імена:
                            виклики = с.п.виклики.get(ф.ід, ())
                            for м2, арг, _ in виклики:
                                if к < len(арг):
                                    вих.update(с.ключі(м2, *арг[к], бачені))
                            if виклики:
                                return вих
                return вих or {('*',)}
        if т[б - 1][1] == ')' and б - 1 in пар:
            о = пар[б - 1]
            if о > а and т[о - 1][1] in с.п.за_ім:
                вих = set()
                арг = с.розділити(т, пар, о + 1, б - 1)
                for ф in с.п.цілі(м, о - 1, т[о - 1][1]):
                    контекст = с.звязати(ф, м, арг)
                    частини = [(ф.а, ф.б)] if ф.вираз else [
                        (і + 1, ф.мод.кінець_виразу(і + 1)) for і in range(ф.а, ф.б)
                        if ф.мод.ток[і][1] == 'return' and ф.мод.охоплює(і) is ф]
                    for х, у in частини:
                        вих.update(с.у_контексті(контекст, с.ключі, ф.мод, х, у, бачені))
                return вих or {('*',)}
        return {('*',)}

    @staticmethod
    def стиснути_ключ(частини):
        """Об'єднує сусідні літеральні частини символічного ключа."""
        вих = []
        for ч in частини:
            if вих and ч != '*' and вих[-1] != '*':
                вих[-1] += ч
            elif not вих or ч != '*' or вих[-1] != '*':
                вих.append(ч)
        return tuple(вих)

    def носій(с, м, а, б, бачені=frozenset()):
        """Доводить localStorage/sessionStorage чи objectStore, включно з callback обгортки."""
        т, пар = м.ток, м.пар
        вузол = (м.шлях, а, б, с.контекст)
        if а >= б or вузол in бачені:
            return set()
        бачені = бачені | {вузол}
        if б - а == 1 and т[а][0] == 'id':
            ім = т[а][1]
            if ім in ('localStorage', 'sessionStorage'):
                return {(ім,)}
            ключ = м.ключ(а, ім)
            зв = с.контексти[с.контекст].get(ключ)
            if зв:
                м2, х, у, контекст = зв
                return с.у_контексті(контекст, с.носій, м2, х, у, бачені)
            вих = set()
            for м2, вид, (х, у), _ in с.п.присв.get(ключ, ()):
                if вид == '=':
                    вих.update(с.носій(м2, х, у, бачені))
            ф = с.п.ф_за_ід.get(ключ[0])
            if ф and any(ім in імена for _, імена in ф.парам):
                # callback передано в обгортку: знаходимо, яким аргументом
                # обгортка його викликає, а не вгадуємо ім'я tx чи параметра.
                for ім2, арг2, і2 in м.виклики:
                    for к, (х, у) in enumerate(арг2):
                        if not х <= ф.заг_а < у:
                            continue
                        for ціль in с.п.цілі(м, і2, ім2):
                            if к >= len(ціль.парам):
                                continue
                            контекст = с.звязати(ціль, м, арг2)
                            імена = ціль.парам[к][1]
                            for вик, арг3, і3 in ціль.мод.виклики:
                                if вик in імена and ціль.мод.ключ(і3, вик) == (ціль.ід, вик) and арг3:
                                    вих.update(с.у_контексті(контекст, с.носій, ціль.мод, *арг3[0], бачені))
            return вих
        if т[б - 1][1] == ')' and б - 1 in пар:
            о = пар[б - 1]
            if о > а and т[о - 1][1] == 'objectStore':
                арг = с.розділити(т, пар, о + 1, б - 1)
                if арг:
                    # Без доведеної єдиної БД сховища різних БД не змішуємо.
                    бази = set()
                    for мод in с.п.модулі:
                        for ім, арг2, і in мод.виклики:
                            if ім == 'open' and і >= 2 and мод.ток[і - 2][1] == 'indexedDB' and арг2:
                                бази.update(с.ключі(мод, *арг2[0]))
                    if len(бази) == 1 and '*' not in next(iter(бази)):
                        return {('indexedDB', next(iter(бази)), к) for к in с.ключі(м, *арг[0])}
        return set()

    def зібрати_писачів(с):
        """Індексує всі писачі API сховищ за носієм і символічним ключем.

        Контексти писачів будуються від кореня, а не від контексту читача, що вперше спитав:
        інакше той самий писач у циклі носіїв мав би чужий контекст і ребра не впізнати.
        """
        с.у_контексті(0, с._зібрати_писачів)

    def _зібрати_писачів(с):
        """Обходить виклики `setItem`/`put`/`add` у кожному контексті їхніх обгорток."""
        с.писачі = []
        for м in с.п.модулі:
            т, пар = м.ток, м.пар
            for ім, арг, і in м.виклики:
                if ім not in ('setItem', 'put', 'add') or і < 2 or т[і - 1][1] not in ('.', '?.') or not арг:
                    continue
                for контекст in с.контексти_місця(м, і):
                    а = і - 2
                    while а >= 0:
                        if т[а][1] in (')', ']') and а in пар:
                            а = пар[а] - 1
                        elif т[а][0] == 'id' or т[а][1] in ('.', '?.'):
                            а -= 1
                        else:
                            break
                    носії = с.у_контексті(контекст, с.носій, м, а + 1, і - 1)
                    if not носії:
                        continue
                    значення = арг[1] if ім == 'setItem' and len(арг) > 1 else арг[0]
                    ключ = арг[0] if ім == 'setItem' else арг[1] if len(арг) > 1 else None
                    ключі = с.у_контексті(контекст, с.ключі, м, *ключ) if ключ else {('*',)}
                    for носій in носії:
                        for к in ключі:
                            с.писачі.append((носій, к, м, значення, контекст, і))

    @staticmethod
    def сумісні(ліва, права):
        """Консервативно перетинає ключі: різні доведені префікси не збігаються."""
        if '*' not in ліва and '*' not in права:
            return ліва == права
        л, п = ''.join(ліва).split('*')[0], ''.join(права).split('*')[0]
        return л.startswith(п) or п.startswith(л)

    def читання(с, носії, ключі, поля):
        """Судить читання за всіма писачами ключа; брак писача лишає явний доказ."""
        if с.писачі is None:
            с.зібрати_писачів()
        вих = set()
        if поля[:1] == ('result',):
            поля = поля[1:]
        for носій in sorted(носії):
            for ключ in sorted(ключі):
                знайдено = False
                for н, к, м, (а, б), контекст, і in с.писачі:
                    if н != носій or not с.сумісні(ключ, к):
                        continue
                    знайдено = True
                    дж = с.у_контексті(контекст, с.вираз, м, а, б, поля)
                    вих.update(дж)
                    с.докази.add('%s:%d · ключ %s · поле %s · %s' % (
                        м.шлях, м.рядок(і), ''.join(к), '.'.join(поля) or 'значення', ', '.join(sorted(назовні(дж)))))
                if not знайдено:
                    вих.add('невідоме')
                    с.докази.add('писач недоведений · %s · ключ %s · поле %s' % (
                        носій, ''.join(ключ), '.'.join(поля) or 'значення'))
        if 'її' in вих and вих & {'стале', 'число'}:
            # Ключ, який пише й вона, і сталий напис чи число коду: не свій текст для читача ключа.
            вих.add(НАПИС)
        return вих or {'невідоме'}

    def каталог(с, м, арг, поля):
        """Шукає писачів завантажуваного файла; назва поля відповіді не доводить її походження."""
        адреси = с.ключі(м, *арг[0]) if арг else {('*',)}
        вих = set()
        for адреса in sorted(адреси):
            знайдено = False
            for мод in с.п.модулі:
                for ім, арг2, і in мод.виклики:
                    if ім not in ('writeFile', 'writeFileSync') or len(арг2) < 2 or not с.файловий_писач(мод, і):
                        continue
                    for контекст in с.контексти_місця(мод, і):
                        імена = с.у_контексті(контекст, с.ключі, мод, *арг2[0])
                        if адреса not in імена or '*' in адреса:
                            continue
                        знайдено = True
                        дж = с.у_контексті(контекст, с.вираз, мод, *арг2[1], поля)
                        вих.update(дж)
                        с.докази.add('%s:%d · файл %s · поле %s · %s' % (
                            мод.шлях, мод.рядок(і), ''.join(адреса), '.'.join(поля) or 'відповідь', ', '.join(sorted(назовні(дж)))))
            if not знайдено:
                вих.add('невідоме')
                с.докази.add('писач недоведений · файл/відповідь %s · поле %s' % (
                    ''.join(адреса), '.'.join(поля) or 'відповідь'))
                с.кандидати_поля(поля)
        return вих or {'невідоме'}

    def кандидати_поля(с, поля):
        """Знаходить писачів поля в Python; збіг поля без доведеного зв'язку з читачем не дає винятку."""
        import ast
        import warnings
        from pathlib import Path
        if not поля or not getattr(с.п, 'корінь', None):
            return
        if с.поля_каталогу is None:
            с.поля_каталогу = {}
            корінь = Path(с.п.корінь)
            for шлях in sorted(корінь.rglob('*.py')):
                if 'node_modules' in шлях.parts or '__pycache__' in шлях.parts:
                    continue
                try:
                    with warnings.catch_warnings():
                        warnings.simplefilter('ignore', SyntaxWarning)
                        дерево = ast.parse(шлях.read_text(encoding='utf-8-sig'))
                except (SyntaxError, UnicodeError) as помилка:
                    с.поля_каталогу.setdefault('*', set()).add(
                        '%s · Python не розібрано: %s' % (шлях.relative_to(корінь).as_posix(), type(помилка).__name__))
                    continue
                for вузол in ast.walk(дерево):
                    записи = []
                    if isinstance(вузол, ast.Dict):
                        записи = [(к.value, з) for к, з in zip(вузол.keys, вузол.values)
                                  if isinstance(к, ast.Constant) and isinstance(к.value, str)]
                    elif isinstance(вузол, ast.Call):
                        записи = [(к.arg, к.value) for к in вузол.keywords if к.arg]
                    elif isinstance(вузол, (ast.Assign, ast.AnnAssign, ast.AugAssign)):
                        цілі = вузол.targets if isinstance(вузол, ast.Assign) else [вузол.target]
                        for ціль in цілі:
                            if isinstance(ціль, ast.Subscript) and isinstance(ціль.slice, ast.Constant) and isinstance(ціль.slice.value, str):
                                записи.append((ціль.slice.value, вузол.value))
                            elif isinstance(ціль, ast.Attribute):
                                записи.append((ціль.attr, вузол.value))
                    for поле, значення in записи:
                        с.поля_каталогу.setdefault(поле, set()).add('%s:%d · %s' % (
                            шлях.relative_to(корінь).as_posix(), вузол.lineno, type(значення).__name__))
        поле = next((п for п in reversed(поля) if п != '*'), '*')
        for доказ in sorted(с.поля_каталогу.get(поле, set()) | с.поля_каталогу.get('*', set())):
            с.докази.add('кандидат писача поля %s · %s · зв’язок із читачем недоведений' % (поле, доказ))

    def файловий_писач(с, м, і):
        """Доводить модуль fs у писача файла, відкидаючи однойменні методи об'єктів."""
        т = м.ток
        if і < 2 or т[і - 1][1] not in ('.', '?.') or т[і - 2][0] != 'id':
            return False
        ключ = м.ключ(і - 2, т[і - 2][1])
        записи = с.п.присв.get(ключ, ())
        if not записи:
            return False
        for мод, вид, (а, б), _ in записи:
            ток = мод.ток[а:б]
            if вид != '=' or len(ток) != 4 or ток[0][1] != 'require' or ток[2][1] not in ('fs', 'node:fs'):
                return False
        return True


def невідповідний(джерела, вид):
    """Звіряє доведене походження з договором входу без числових порогів."""
    if вид in ('проза', 'збій'):
        return False
    дозволені = {'стале', 'число', 'перевірено'}
    if вид == 'назва':
        дозволені |= {'назва', 'її'}
        if 'назва' in джерела:
            дозволені.add('складено')
    elif вид == 'її':
        # Сталий допис разом із її словами вже позначено «складено».
        дозволені |= {'її', 'назва'}
    else:
        дозволені |= {'її', 'вузол', 'елемент'}
    return not джерела <= дозволені
