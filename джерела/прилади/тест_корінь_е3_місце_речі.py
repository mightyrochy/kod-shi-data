class ТаблицяФункцією(unittest.TestCase):
    """14268: та сама таблиця місця — стала, функція з `if`-ланцюгом, `dict` у тілі чи `a if … else b` — лічиться однаково."""

    ФОРМИ = {
        "ланцюг": """
def _ярус_крою(слот):
    if слот == "верх":
        return "верх"
    if слот == "верхній_шар":
        return "верх"
    if слот == "низ":
        return "низ"
    return None
""",
        "словник у тілі": """
def _ярус_крою(слот):
    return {"верх": "верх", "верхній_шар": "верх", "низ": "низ"}.get(слот)
""",
        "локальний словник": """
def _ярус_крою(слот):
    таблиця = {"верх": "верх", "верхній_шар": "верх", "низ": "низ"}
    return таблиця[слот] if слот in таблиця else None
""",
        "a if … else b": """
def _ярус_крою(слот):
    return "верх" if слот in ("верх", "верхній_шар") else "низ" if слот == "низ" else None
""",
        "ім'я поза словником": """
def _рівень(слот):
    if слот in ("верх", "верхній_шар"):
        return "верх"
    return "низ" if слот == "низ" else None
""",
    }
    ВИКЛИК = """
def ярус(слот, тіло):
    return тіло.get({ім}(слот))
def ще(слот):
    return {ім}(слот)
"""

    def місця_форми(self, текст, ім):
        файли = {"композитор_слоти.py": текст + self.ВИКЛИК.format(ім=ім)}
        п, м = форма(файли)
        виклики = {н for н in (рядки_з(файли, "композитор_слоти.py", ім + "(слот)")) if м.get(("композитор_слоти.py", н))}
        return п, м, виклики

    def test_стала_і_функція_дають_однакове_число(self):
        п, м = форма({"композитор_слоти.py": ТАБЛИЦЯ_СТАЛОЮ})
        ДО = sum(1 for к, (пп, _, _) in м.items() if к[0] == "композитор_слоти.py" and пп == 1)
        self.assertEqual(ДО, 2, "стала: два читання")
        for назва, текст in self.ФОРМИ.items():
            ім = "_ярус_крою" if "_ярус_крою" in текст else "_рівень"
            with self.subTest(форма=назва):
                п, м, виклики = self.місця_форми(текст, ім)
                self.assertIn(("композитор_слоти", ім), п.таблиці)
                self.assertTrue(п.таблиці[("композитор_слоти", ім)]["функція"])
                self.assertEqual(len(виклики), 2, "обидва виклики — місця п.1, як читання сталої")
                self.assertTrue(all(м[("композитор_слоти.py", н)][0] == 1 for н in виклики))
                self.assertEqual(sum(1 for к in м if к[0] == "композитор_слоти.py"), ДО,
                                 "визначення функції (її порівняння зі слотами) місць не додає")

    def test_обгортка_над_функцією_відображенням(self):
        п, м, _ = self.місця_форми(self.ФОРМИ["ланцюг"], "_ярус_крою")
        self.assertIn(("композитор_слоти", "ще"), п.обгортки, "функція, що вертає виклик відображення, — обгортка")

    def test_не_відображення(self):
        for назва, текст in (
                ("переклад один до одного", 'def _англійською(слот):\n    return {"верх": "top", "низ": "bottom", "сукня": "dress"}.get(слот)\n'),
                ("переклад слота у слот", 'def _переклад(слот):\n    return {"top": "верх", "bottom": "низ"}.get(слот)\n'),
                ("предикат", 'def _зона_довга(слот):\n    return слот in ("верх", "верхній_шар")\n'),
                ("значення — родина, ім'я поза словником", 'def _родина(слот):\n    if слот in ("верх", "низ"):\n        return "одяг"\n    return "прикраси" if слот == "сумка" else None\n'),
                ("один слот", 'def _ярус_крою(слот):\n    if слот == "верх":\n        return "верх"\n    return None\n'),
                ("не літерал у поверненні", 'def _ярус_крою(слот, х):\n    if слот == "верх":\n        return "верх"\n    return х\n')):
            with self.subTest(форма=назва):
                п, _ = форма({"композитор_слоти.py": текст})
                self.assertFalse([к for к in п.таблиці if к[0] == "композитор_слоти"], "це не таблиця місця")

    def test_стала_за_змістом_без_слова_про_місце(self):
        п, м = форма({"композитор_слоти.py": '_ШАРИ = {"верх": "верх", "верхній_шар": "верх", "низ": "низ"}\n'
                                             'def в(слот):\n    return _ШАРИ.get(слот)\n'})
        self.assertIn(("композитор_слоти", "_ШАРИ"), п.таблиці, "проєкція слотів на яруси тіла — таблиця за змістом")
        п, м = форма({"композитор_слоти.py": '_ЧАСТИНА = {"верх": "top", "низ": "bottom", "сукня": "dress"}\n'
                                             'def в(слот):\n    return _ЧАСТИНА.get(слот)\n'})
        self.assertNotIn(("композитор_слоти", "_ЧАСТИНА"), п.таблиці, "переклад — не місце")

    def test_не_таблиця_з_причиною_поіменно(self):
        П.НЕ_ТАБЛИЦІ[("композитор_слоти.py", "_ярус_крою")] = "тест: ярус для тексту"
        try:
            п, м, виклики = self.місця_форми(self.ФОРМИ["ланцюг"], "_ярус_крою")
            self.assertEqual(виклики, set())
            self.assertIn(("композитор_слоти.py", "_ярус_крою"), п.не_таблиці)
        finally:
            del П.НЕ_ТАБЛИЦІ[("композитор_слоти.py", "_ярус_крою")]


class ЛітералАбоСтала(unittest.TestCase):
    """14248: місце лічиться однаково, літерал це чи іменована стала (своя, імпортована, через модуль)."""

    ФАЙЛИ = {
        "місце.py": 'ВЕРХНІЙ_ШАР = "верхній_шар"\nСЛОТИ_УБОРУ = ("головний_убір", "headwear")\n'
                    'ДВІ = ("верх", "низ")\nДАЛІ = ДВІ + ("сукня",)\n',
        "літерал.py": 'def на_голові(р):\n    return р.get("слот") in ("головний_убір", "headwear")\n',
        "стала.py": 'СЛОТИ_УБОРУ = ("головний_убір", "headwear")\n'
                    'def на_голові(р):\n    return р.get("слот") in СЛОТИ_УБОРУ\n',
        "імпорт.py": 'import місце as _М\nfrom місце import СЛОТИ_УБОРУ as Г\n'
                     'def на_голові(р):\n    return р.get("слот") in _М.СЛОТИ_УБОРУ\n'
                     'def в_голові(р):\n    return р.get("слот") in Г\n'
                     'def шар_голови(р):\n    return р.get("слот") == _М.ВЕРХНІЙ_ШАР\n',
        "затінено.py": 'СЛОТИ_УБОРУ = ("головний_убір", "headwear")\n'
                       'def на_голові(р, СЛОТИ_УБОРУ):\n    return р.get("слот") in СЛОТИ_УБОРУ\n',
        "двічі.py": 'СЛОТИ_УБОРУ = ("головний_убір",)\nСЛОТИ_УБОРУ = ("headwear",)\n'
                    'def на_голові(р):\n    return р.get("слот") in СЛОТИ_УБОРУ\n',
        "не_слоти.py": 'ПРИЗНАКИ = ("колір", "розмір")\ndef на_голові(р):\n    return р.get("ознака") in ПРИЗНАКИ\n',
    }

    def п3(self, файл):
        _, м = форма(self.ФАЙЛИ)
        return sorted(н for (ф, н), (п, _, _) in м.items() if ф == файл and п == 3)

    def test_літерал_стала_імпорт_однаково(self):
        self.assertEqual(len(self.п3("літерал.py")), 1)
        self.assertEqual(len(self.п3("стала.py")), 1, "іменована стала модуля — те саме місце, що літерал")
        self.assertEqual(len(self.п3("імпорт.py")), 3, "імпорт через модуль, `from … import … as …` і сталу рядка")

    def test_затінена_чи_двічі_присвоєна_не_розкривається(self):
        self.assertEqual(self.п3("затінено.py"), [], "параметр з іменем сталої — не стала")
        self.assertEqual(self.п3("двічі.py"), [], "стала, присвоєна двічі, невідомо яка — не розкривається")
        self.assertEqual(self.п3("не_слоти.py"), [], "кортеж не слотів — не слоти")

    def test_таблиця_за_іменем_не_розкривається(self):
        п, м = форма({"таблиця.py": 'ПОВЕРХ_ГОЛОВИ = ("headwear", "головний_убір")\n'
                                    'def х(р):\n    return р["слот"] in ПОВЕРХ_ГОЛОВИ\n'})
        self.assertIn(("таблиця", "ПОВЕРХ_ГОЛОВИ"), п.таблиці)
        self.assertEqual(sum(1 for (ф, _), (пп, _, _) in м.items() if ф == "таблиця.py" and пп == 1), 1,
                         "таблиця місця лічиться п.1, а не розкривається в літерал")

    def test_не_місце_поіменно_літерал_і_стала(self):
        ключ = ("літерал.py", "на_голові", "headwear|головний_убір")
        ключ2 = ("стала.py", "на_голові", "headwear|головний_убір")
        П.НЕ_МІСЦЯ_ЛОГІКИ[ключ] = П.НЕ_МІСЦЯ_ЛОГІКИ[ключ2] = "тест: класифікація типу"
        try:
            п, м = форма(self.ФАЙЛИ)
            for файл in ("літерал.py", "стала.py"):
                with self.subTest(файл=файл):
                    self.assertFalse([1 for (ф, _), (пп, _, _) in м.items() if ф == файл and пп == 3],
                                     "названа причина знімає і літерал, і сталу однаково")
            self.assertEqual(set(п.не_логіка), {ключ, ключ2})
            self.assertEqual(len([1 for (ф, _), (пп, _, _) in м.items() if ф == "імпорт.py" and пп == 3]), 3,
                             "запис діє лише на свою функцію")
        finally:
            del П.НЕ_МІСЦЯ_ЛОГІКИ[ключ], П.НЕ_МІСЦЯ_ЛОГІКИ[ключ2]


if __name__ == "__main__":
    unittest.main()
