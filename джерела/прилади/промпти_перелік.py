def _норм(т):
    """Текст для порівняння: малі літери, без лапок і зайвих пробілів."""
    return re.sub(r"\s+", " ", re.sub(r"[\"«»“”'`]", "", т.lower())).strip()


def речення(т):
    """Речення розділу (≥ 40 знаків) для пошуку однакових між промптами."""
    return [р.strip() for р in re.split(r"(?<=[.;!?])\s+(?=[A-ZА-ЯІЇЄҐ\"«(])", т) if len(р.strip()) >= 40]


def дублі_речень(сталі):
    """{норм. речення: [(клас, розділ, текст)]} — речення, що стоять у ≥ 2 місцях сталих розділів."""
    де = collections.defaultdict(list)
    for кл, імя, текст in сталі:
        for р in речення(текст):
            де[_норм(р)].append((кл, імя, р))
    return {к: в for к, в in де.items() if len(в) >= 2}


def майже_однакові(сталі, поріг=0.8):
    """Пари сталих розділів (≥ 80 знаків) з різних місць, схожі на ≥ `поріг` (difflib), але не рівні."""
    кандидати = [(кл, імя, т, set(zip(*[iter(_норм(т).split())] * 1))) for кл, імя, т in сталі if len(т) >= 80]
    сл = [(кл, імя, т, set(_норм(т).split())) for кл, імя, т, _ in кандидати]
    вих = []
    for і in range(len(сл)):
        for j in range(і + 1, len(сл)):
            а, б = сл[і], сл[j]
            if а[2] == б[2] or not а[3] or not б[3]:
                continue
            if len(а[3] & б[3]) / len(а[3] | б[3]) < 0.55:
                continue
            р = difflib.SequenceMatcher(None, _норм(а[2]), _норм(б[2]), autojunk=False).ratio()
            if р >= поріг:
                вих.append((р, а[:3], б[:3]))
    return sorted(вих, key=lambda x: -x[0] * min(len(x[1][2]), len(x[2][2])))


def дублі_даних(о):
    """Рядкові значення ≥ 40 знаків, що стоять у даних одного промпту ≥ 2 разів: [(разів, довжина, початок)]."""
    к = collections.Counter()

    def обхід(в, у_task):
        """Лічить рядкові значення даних (поза task) у `к`."""
        if isinstance(в, dict):
            for кк, вв in в.items():
                обхід(вв, у_task or кк == "task")
        elif isinstance(в, list):
            for x in в:
                обхід(x, у_task)
        elif isinstance(в, str) and len(в) >= 40 and not у_task:
            к[в] += 1
    обхід(о, False)
    return [(н, len(т), т[:50]) for т, н in к.most_common() if н >= 2]


