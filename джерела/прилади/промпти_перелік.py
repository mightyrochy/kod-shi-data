class Джерела:
    """Індекс текстів джерел для відбитків: де в коді лежить текст розділу, і `git blame` того рядка."""

    ФАЙЛИ = ("*.py", "показ.html", "*.js")

    def __init__(self):
        self.тексти = {}
        for маска in self.ФАЙЛИ:
            for ф in glob.glob(os.path.join(ДЖЕРЕЛА, маска)):
                імя = os.path.basename(ф)
                if not імя.startswith(("тест_", "worker.js")) and "node_modules" not in ф:
                    self.тексти["джерела/" + імя] = open(ф, encoding="utf-8", errors="replace").read()
        self.рядки = {ф: т.splitlines() for ф, т in self.тексти.items()}
        self.знайдено = {}
        self.blame = {}
        self.повідомлення = {}

    def знайти(self, текст):
        """(файл, номер рядка від 1) першого вікна тексту розділу, що є в джерелах, або None."""
        if текст in self.знайдено:
            return self.знайдено[текст]
        вих = None
        for шмат in re.split(r'["\\\n]|%s|%d| — |; |: ', текст):
            # рядок входу збирач пише як «"поле" — що; як»: «— » і «; » стоять між шматками джерела
            шмат = шмат.strip(" —;:,.")
            for поч in sorted(set(list(range(0, max(1, len(шмат) - 24), 20)) + [max(0, len(шмат) - 32)])):
                вікно = шмат[поч:поч + 32].strip()
                if len(вікно) < 20:
                    continue
                for ф, т in self.тексти.items():
                    і = т.find(вікно)
                    if і >= 0:
                        вих = (ф, т.count("\n", 0, і) + 1)
                        break
                if вих:
                    break
            if вих:
                break
        self.знайдено[текст] = вих
        return вих

    def охопна(self, ф, н):
        """Функція чи стала, у якій лежить рядок `н` файлу `ф`."""
        return _охопна(self.рядки[ф], н - 1) or "?"

    def рядки_дошки(self, ф, н):
        """Рядки дошки й PR з коментаря над рядком джерела (до 14 рядків коментаря поспіль)."""
        текст, р = [], self.рядки[ф]
        for x in reversed(р[max(0, н - 16):н]):
            if re.match(r"\s*(#|//|/\*|\*)", x) or текст == [] or x.strip().endswith(("(", ",", "+")):
                текст.append(x)
            else:
                break
        return _рядки(" ".join(текст))

    def походження(self, ф, н):
        """(sha7, дата, тема коміту, рядки дошки з повідомлення коміту) останньої зміни рядка."""
        if ф not in self.blame:
            self.blame[ф] = {}
        if н not in self.blame[ф]:
            сире = git("blame", "--line-porcelain", "-L", "%d,%d" % (н, н), ГОЛОВА, "--", ф).decode("utf-8", "replace")
            sha = сире.split(" ", 1)[0]
            час = re.search(r"^author-time (\d+)", сире, re.M)
            self.blame[ф][н] = (sha, int(час.group(1)) if час else 0)
        sha, час = self.blame[ф][н]
        if sha not in self.повідомлення:
            self.повідомлення[sha] = git("log", "-1", "--format=%ad%x00%s%x00%b", "--date=short", sha).decode(
                "utf-8", "replace").split("\x00")
        дата, тема, тіло = self.повідомлення[sha]
        return sha[:8], дата, тема, _рядки(тема + " " + тіло)


def _рядки(т):
    """Номери рядків дошки (3–4 цифри після «рядок/рядки/рядку») і PR (#NNN) з тексту."""
    рядки = []
    for м in re.finditer(r"ряд(?:ок|к\w*)\s+((?:\d{3,4}(?:[–\-]\d{3,4})?(?:,\s*|\s+і\s+)?)+)", т):
        рядки += re.findall(r"\d{3,4}(?:[–\-]\d{3,4})?", м.group(1))
    pr = re.findall(r"#(\d{3,4})\b", т)
    return list(dict.fromkeys(рядки)), list(dict.fromkeys(pr))


