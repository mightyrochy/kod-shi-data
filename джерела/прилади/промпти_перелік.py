def промпт_файлу(т):
    """Текст промпту з файлу VIDPOVIDI (без заголовка й відповіді)."""
    return т.split("\n", 1)[1].split(МЕЖА_ПРОМПТУ)[0] if "\n" in т else т


def _номер(імя):
    """Порядковий номер виклику з імені `seedN_NN_тип.txt`."""
    м = re.match(r"seed\d+_(\d+)_", імя)
    return int(м.group(1)) if м else 0


def записи_тек(пари):
    """Записи заглушки: [{набір, сцена, n, промпт, модель, ток_моделі}] з тек `назва=тека`."""
    вих = []
    for назва, тека in пари:
        for ф in sorted(glob.glob(os.path.join(тека, "*.txt")), key=lambda ф: _номер(os.path.basename(ф))):
            with open(ф, encoding="utf-8", errors="replace") as д:
                вих.append(dict(набір="заглушка", сцена=назва, n=_номер(os.path.basename(ф)),
                                промпт=промпт_файлу(д.read()), модель=None, ток_моделі=None))
    return вих


def _вміст_гілки(ref, шляхи):
    """{шлях: текст} одним `git cat-file --batch` (без checkout гілки)."""
    вхід = "".join("%s:%s\n" % (ref, ш) for ш in шляхи).encode("utf-8")
    сирі, вих, і = git("cat-file", "--batch", вхід=вхід), {}, 0
    for ш in шляхи:
        кін = сирі.index(b"\n", і)
        голова = сирі[і:кін].split()
        if голова[-1] == b"missing":
            і = кін + 1
            continue
        розмір = int(голова[2])
        вих[ш] = сирі[кін + 1:кін + 1 + розмір].decode("utf-8", "replace")
        і = кін + 1 + розмір + 1
    return вих


