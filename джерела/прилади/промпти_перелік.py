def токени(т):
    """Токени Gemma 3 (GEMMA_TOKENIZER) або None без токенізатора."""
    global _ТОК
    if _ТОК is None:
        шлях = os.environ.get("GEMMA_TOKENIZER")
        if not шлях:
            _ТОК = False
        else:
            from tokenizers import Tokenizer
            _ТОК = Tokenizer.from_file(шлях)
    return len(_ТОК.encode(т, add_special_tokens=False).ids) if _ТОК else None


def git(*арг, вхід=None):
    """Вивід git (байти) з кореня; помилка — виняток із текстом git."""
    р = subprocess.run(["git", "-c", "core.quotepath=off"] + list(арг), cwd=КОРІНЬ, input=вхід,
                       capture_output=True)
    if р.returncode:
        raise RuntimeError("git %s: %s" % (" ".join(арг[:3]), р.stderr.decode("utf-8", "replace")[:300]))
    return р.stdout


