def _ім(н):
    if isinstance(н, ast.Name):
        return н.id
    if isinstance(н, ast.Attribute):
        return н.attr
    if isinstance(н, ast.Subscript):
        с = н.slice
        if isinstance(с, ast.Constant) and isinstance(с.value, str):
            return с.value
        return _ім(н.value)
    return ""


def _вузли(тіло):
    """Вузли тіла без вкладених функцій і класів."""
    стос = list(тіло)
    while стос:
        х = стос.pop()
        yield х
        for д in ast.iter_child_nodes(х):
            if not isinstance(д, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda, ast.ClassDef)):
                стос.append(д)


def _журнальний(виклик):
    ф = виклик.func
    return (ф.attr if isinstance(ф, ast.Attribute) else getattr(ф, "id", "")) in ЖУРНАЛ_PY


def авто_py(о):
    """(вид, чому) для обробника Python чи None — потрібен вердикт."""
    о_ = о["вузол"]
    вузли = list(_вузли(о_.body))
    for х in вузли:
        if isinstance(х, ast.Raise):
            return "слід", "raise"
        if isinstance(х, ast.Call):
            ф = ast.unparse(х.func)
            if ф in ("sys.exit", "exit", "SystemExit", "os._exit"):
                return "слід", ф
            if isinstance(х.func, ast.Attribute) and х.func.attr in ДОПИСАТИ and ЗБІЙ_ІМ.search(_ім(х.func.value)):
                return "слід", "дописано в %s" % _ім(х.func.value)
        if isinstance(х, ast.Constant) and isinstance(х.value, str) and РЯДОК_СЛІДУ.search(х.value):
            return "слід", "рядок «%s»" % х.value[:30]
        if isinstance(х, ast.Dict):
            for к in х.keys:
                if isinstance(к, ast.Constant) and к.value in КЛЮЧІ_СЛІДУ:
                    return "слід", "ключ «%s»" % к.value
        if isinstance(х, ast.keyword) and х.arg and (х.arg in КЛЮЧІ_СЛІДУ or х.arg in ("що", "де")):
            return "слід", "поле «%s»" % х.arg
        if isinstance(х, (ast.Assign, ast.AugAssign, ast.AnnAssign)):
            for ц in (х.targets if isinstance(х, ast.Assign) else [х.target]):
                for цц in (ц.elts if isinstance(ц, ast.Tuple) else [ц]):
                    if ЗБІЙ_ІМ.search(_ім(цц)):
                        return "слід", "поле збою «%s»" % _ім(цц)
        if (isinstance(х, ast.Return) and isinstance(х.value, ast.Constant) and isinstance(х.value.value, str)
                and КОД_ПРИЧИНИ.match(х.value.value)):
            return "слід", "код причини «%s»" % х.value.value
    if о_.name:
        журнальні = {id(в) for х in вузли if isinstance(х, ast.Call) and _журнальний(х) for в in ast.walk(х)}
        журнальні |= {id(в) for х in вузли if isinstance(х, (ast.If, ast.IfExp, ast.While)) for в in ast.walk(х.test)}
        for х in вузли:
            if isinstance(х, ast.Name) and х.id == о_.name and id(х) not in журнальні:
                if isinstance(х.ctx, ast.Load):
                    return "слід", "виняток у значенні"
    типи = set()
    if о_.type is not None:
        for т in (о_.type.elts if isinstance(о_.type, ast.Tuple) else [о_.type]):
            типи.add(ast.unparse(т))
    if типи and типи <= ПОТІК_PY:
        return "потік", "очікуваний потік (%s)" % ", ".join(sorted(типи))
    return None


def обробники_py(шлях, текст):
    """Обробники `except` файлу Python: список словників кандидата."""
    try:
        дерево = ast.parse(текст)
    except SyntaxError:
        return []
    вих = []

    def обхід(вузол, функція, лік):
        for д in ast.iter_child_nodes(вузол):
            if isinstance(д, (ast.FunctionDef, ast.AsyncFunctionDef)):
                обхід(д, (функція + "." if функція != "<модуль>" else "") + д.name, {})
                continue
            if isinstance(д, ast.ClassDef):
                обхід(д, (функція + "." if функція != "<модуль>" else "") + д.name, {})
                continue
            if isinstance(д, ast.ExceptHandler):
                лік[0] = лік.get(0, 0) + 1
                вих.append(dict(файл=шлях, рядок=д.lineno, мова="py", функція=функція, номер=лік[0],
                                тип=ast.unparse(д.type) if д.type is not None else "bare",
                                тіло=" ; ".join(ast.unparse(с) for с in д.body), вузол=д))
            обхід(д, функція, лік)

    обхід(дерево, "<модуль>", {})
    return вих


