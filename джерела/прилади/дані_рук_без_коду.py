"""Промпти рук 3–4 даними для ядра (`джерела/ядро/дані/руки_без_коду.json`), байт у байт з чинного `руки_без_коду`.

Руки 3–4 «лишати, не міняти» (власник 18.09, 16.10; `РЕЗУЛЬТАТ.md`, §6.2, М5): ядро не пише промпт наново, а бере
відрендерену частину `task` чинного збирача для кожного набору полів, які має вхід, і кладе поля даних тим самим
порядком. Запуск: `python3 прилади/дані_рук_без_коду.py` з `джерела/`; тест ядра (`тест_н3`) звіряє, що дані
досі збігаються з чинним промптом.
"""
import itertools
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import руки_без_коду as Р  # noqa: E402
import внутрішня_мова as ВМ  # noqa: E402

ПОЛЯ = ("main_color", "person")   # необов'язкові поля, які ядро вміє дати; `case` — завжди
ЗНАК = "__ПОЛЕ__"


def задача(поля, рука):
    дані = dict(випадок={ЗНАК: "case"}, вибір=None, факти=None)
    if "main_color" in поля:
        Р.головний_колір = lambda _в: {ЗНАК: "main_color"}  # noqa: E731 — підстава, щоб узяти лише `task`
    дані["факти"] = {ЗНАК: "person"} if "person" in поля else None
    т = json.loads(Р.промпт_руки(рука, дані["випадок"], "", дані["вибір"], None, дані["факти"]))
    return т["task"], [к for к in т if к != "task"]


def main():
    справжній = Р.головний_колір
    вих = {"_опис": __doc__.split("\n\n")[0], "образ": {}, "порядок": {}}
    for рука in ("3", "4"):
        for n in range(len(ПОЛЯ) + 1):
            for набір in itertools.combinations(ПОЛЯ, n):
                if "person" in набір and рука == "4":
                    continue
                Р.головний_колір = справжній
                т, порядок = задача(набір, рука)
                ключ = "+".join(("case",) + набір)
                вих["образ"][ключ] = т
                вих["порядок"][ключ] = порядок
    Р.головний_колір = справжній
    перелік = json.loads(Р.промпт_переліку(None))
    вих["перелік"] = {"task": перелік["task"], "порядок": [к for к in перелік if к != "task"]}
    вих["слоти"] = {к: Р._слот_за_назвою(к) for к in ВМ.ТАБЛИЦЯ["slot"]}
    шлях = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "ядро", "дані", "руки_без_коду.json")
    with open(шлях, "w", encoding="utf-8") as ф:
        json.dump(вих, ф, ensure_ascii=False, indent=1)
        ф.write("\n")
    print(шлях, len(вих["образ"]))


if __name__ == "__main__":
    main()
