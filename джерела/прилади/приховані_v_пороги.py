# -*- coding: utf-8 -*-
"""Приховані-розвідка, частина (в), одиниці Л: кожен голий поріг проти чисел корпусу правил його функції.

Одиниці — `приховані_v_обсяг.пороги` (порівняння з числовим літералом поза `БЕЗПЕЧНІ` у функції модуля, що виконує
правила). Для кожної: ід правил, що стоять у тілі функції (`ід_правил.бази_в_тексті`), і чи є число порогу в означенні
цих правил (`правила.формулювання`) чи поряд з ід у корпусі (±600 знаків) — та сама звірка, що для констант реєстру
(`приховані_v_обсяг._збіг`).

Вердикт (колонка 4):
  з_означення:<ід>      число є в означенні правила функції — поріг несе число корпусу, але голим літералом, без
                        тіру й провенансу (стелі сили `реєстр_тіри` не голосує);
  поряд:<ід>            збіг лише поряд з ід (корпус часто описує сам код — коловий збіг);
  не_в_корпусі:<ід,…>   правило в функції є, числа в корпусі нема — число ставить код (В6) і реєстр його не бачить;
  без_правила           у функції жодного ід — поріг без мірки корпусу (службовий чи стилю — рядок переліку).
Запуск з кореня: `python3 джерела/прилади/приховані_v_пороги.py [--усі]`; `--усі` — рядок на поріг:
ід ⇥ місце ⇥ функція · вираз ⇥ вердикт ⇥ ознаки `приховані_v_обсяг`.
"""
import ast
import os
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import приховані_v_обсяг as V  # noqa: E402
import ід_правил as ІП  # noqa: E402


def _функції(ф):
    """[(початок, кінець, тіло)] функцій модуля — найглибша, що містить рядок, перша з кінця."""
    рядки = open(ф, encoding="utf-8").read().splitlines()
    return [(в.lineno, в.end_lineno, "\n".join(рядки[в.lineno - 1:в.end_lineno])) for в in ast.walk(V._ast(ф))
            if isinstance(в, (ast.FunctionDef, ast.AsyncFunctionDef))]


def вердикти():
    К = V.корпус()
    функції = {}
    out = []
    for п in V.пороги(V.константи()):
        ф, н = п["місце"].rsplit(":", 1)
        н = int(н)
        фф = функції.setdefault(ф, _функції(os.path.join(V.КОРІНЬ, ф)))
        тіло = min((ф_ for ф_ in фф if ф_[0] <= н <= ф_[1]), key=lambda ф_: ф_[1] - ф_[0])[2]
        іди = sorted(set(ІП.бази_в_тексті(тіло)))
        ч = [float(п["ід"].rsplit(":", 1)[1])]
        в = None
        for ід in іди:
            if V._збіг(ч, V._числа_тексту(К["озн"].get(ід, ""), ід)):
                в = "з_означення:" + ід
                break
        if not в:
            for ід in іди:
                if V._збіг(ч, V._числа_тексту(V._поряд(ід), ід)):
                    в = "поряд:" + ід
                    break
        if not в:
            в = "не_в_корпусі:" + ",".join(іди[:4]) if іди else "без_правила"
        out.append(dict(ід=п["ід"], місце=п["місце"], опис=п["опис"], вердикт=в, ознаки=п["ознаки"]))
    return out


def main():
    вв = вердикти()
    if "--усі" in sys.argv:
        for в in вв:
            print("\t".join([в["ід"], в["місце"], в["опис"], в["вердикт"], ";".join(в["ознаки"])]))
    л = Counter(в["вердикт"].split(":")[0] for в in вв)
    print("порогів: %d · %s" % (len(вв), ", ".join("%s %d" % (к, н) for к, н in л.most_common())))
    print("місць: %d" % sum(1 for в in вв if not в["вердикт"].startswith(("з_означення", "поряд"))))


if __name__ == "__main__":
    main()
