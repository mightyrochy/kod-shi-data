# -*- coding: utf-8 -*-
"""Перевіряє межу нового входу та походження запису на малих програмах."""
import ast
import os
import tempfile
import unittest

from корінь_річ_кадр_варіант import зібрати_одиниці, суд_місць, присвоєння, рядки_імен
from походження_запису import константи_імпортів


def місця(код):
    """Судить фрагмент виробника без запуску продукту."""
    дерево = ast.parse(код)
    рез = []
    for ім, вузол, тіло, з in зібрати_одиниці(дерево):
        з.функції = {н.name: н for н in дерево.body if isinstance(н, ast.FunctionDef)}
        рез.extend(суд_місць("zhnyvarka/приклад.py", ім, вузол, тіло, з, з.батьки, False))
    return рез


class МежаЗапису(unittest.TestCase):
    """Перестановка назв змінних не має міняти походження запису."""

    def test_конфігурація(self):
        """Ваги, селектори, рецепти й аргумент суду не є речами."""
        код = '''
КОРИСНІ = {"фото": (4, "адреси"), "колір": (1, "слово"), "наявність": (3, "стан")}
def рецепт():
    return dict(колір=("Color", "Colour"))
def читати(html, lab):
    порівняти(dict(lab=tuple(lab)))
    return dict(кадри_джерело='img[itemprop="image"]', фото_джерело='.gallery img')
'''
        self.assertFalse([м for м in місця(код) if м.статус == "порушує"])

    def test_похідне(self):
        """Копія й посилання на сестер не створюють нового входу."""
        код = '''
def копія(річ, сестри):
    return dict(фото=річ["фото"], колір=річ.get("колір"),
                варіанти_кольору=[с["колір"] for с in сестри])
'''
        self.assertTrue(all(м.статус == "поза класом" for м in місця(код)))

    def test_вхід(self):
        """DOM і regex доходять до запису через кілька присвоєнь."""
        код = '''
def читати(html):
    знайдено = re.search("color=(.*)", html)
    слово = знайдено.group(1)
    інше = слово
    return dict(колір=інше, фото=soup.select_one("img").get("src"))
'''
        self.assertEqual([(м.пункт, м.статус) for м in місця(код)], [(2, "порушує"), (1, "порушує")])

    def test_оферта(self):
        """Власна оферта визначається id і наявністю з того самого входу."""
        for назва in ("дані", "товар", "варіант"):
            код = f'''\ndef читати({назва}):
    return dict(id={назва}.get("id"), available={назва}.get("available"),
                колір={назва}.findtext("color"), фото={назва}.findtext("picture"))
'''
            self.assertTrue(all(м.статус in ("дотримує", "поза класом") for м in місця(код)))
        self.assertTrue(all(м.статус in ("дотримує", "поза класом") for м in місця('''
def читати(дані):
    return {"id": дані.get("id"), "available": дані.get("available"), "колір": дані.findtext("color")}
''')))

    def test_словник_аргумент(self):
        """Літерал усередині логічного аргументу має ту саму межу, що dict()."""
        self.assertFalse([м for м in місця('''
def читати(зб, кадр):
    return порівняти(зб or {"фото": кадр})
''') if м.статус != "поза класом"])

    def test_чужий_колір(self):
        """Колір сестри не доводить власний колір за однакової назви запису."""
        код = '''
def читати(оферта, сестра):
    return dict(id=оферта.get("id"), available=оферта.get("available"), колір=сестра.findtext("color"))
'''
        self.assertEqual([м.статус for м in місця(код) if м.ключ == "колір"], ["порушує"])

    def test_атрибут_кортеж(self):
        """Однакове походження має однаковий суд для різних форм запису."""
        код = '''
def читати(html, запис, таблиця):
    колір = re.search("color=(.*)", html).group(1)
    запис.колір = колір
    таблиця.append(("url", колір))
'''
        self.assertEqual(len([м for м in місця(код) if м.статус == "порушує"]), 2)

    def test_вікно_слова(self):
        """Проміжний сегмент без нового входу не стає записом речі."""
        код = '''
def вікно(сегмент):
    return dict(сегмент, колір_тип="інтервал", колір_не_вимір=сегмент.get("джерело"))
'''
        self.assertTrue(all(м.статус == "поза класом" for м in місця(код)))

    def test_regex_готового_поля(self):
        """Regex над готовим полем не є новим входом крамниці."""
        код = '''
def перетворити(запис):
    слово = re.search("color=(.*)", запис["опис"]).group(1)
    return dict(колір=слово)
'''
        self.assertTrue(all(м.статус == "поза класом" for м in місця(код)))

    def test_числове_зведення(self):
        """Лічильники в другій позиції кортежу не наслідують джерело першої."""
        код = '''
def звести(поверхні):
    кадри = dict(усього=len(поверхні), обрано=None, розкид=None)
    return поверхні[0], кадри
def виміряти(шлях):
    вимір = поверхня_фото(шлях)
    _, кадри = звести(вимір)
    return dict(вимір, кадри=кадри)
'''
        self.assertFalse([м for м in місця(код) if м.ключ == "кадри" and м.статус == "порушує"])

    def test_константа_іншого_модуля(self):
        """Псевдонім імпорту й ланцюг шляхів розкривають назву файла."""
        д = ast.parse('import модуль as М\nшлях = os.path.join(ТУТ, М.ІМ + ".gz")\nтимчасовий = шлях + ".tmp"')
        імпорти = константи_імпортів(д, ".", lambda т, і: ast.parse('ІМ="каталог.json"'))
        значення = присвоєння(д.body, імпорти)
        self.assertIn("каталог.json", рядки_імен(ast.parse("тимчасовий", mode="eval"), значення))


if __name__ == "__main__":
    unittest.main()
