# Уточнення класу 13.11 (паспорт Річ-кадр-варіант, «Рішення»): колір кадру з доведеним власником і запис доказу власності.
ДОКАЗ_ЗАПИСУ = '''
def доказ_варіанта(o, url):
    власник = json.loads(o["параметри"].get("власник_кадру") or '"невідомо"')
    звязки = власник.get("зв_язки")
    ід = звязки.get(url)
    if not ід or not all(і in власник["варіанти"] for і in ід):
        return None
    return dict(варіант="%s:%s" % (власник["товар"], ід[0]), адреса=o["url"], кадр=url)
'''
ВИМІР = '''
def походження_кадру(o, фото):
    з = dict(url=фото["url"], sha256=None)
    з["sha256"] = hashlib.sha256(open(фото["шлях"], "rb").read()).hexdigest()
    return з
def обробити(o, фото):
    доказ = доказ_кадру(o, фото)
    основний = поверхня_фото(фото["шлях"])
    після = походження_кадру(o, фото)
    після["власник_кадру"] = доказ["варіант"] if доказ else "невідомо"
    return dict(колір_основний=КОЛІР, кадр_виміру=КАДР, власник_кадру=ВЛАСНИК)
'''


def колір_виміру(колір="основний if доказ else None", кадр="після", власник='після["власник_кадру"]'):
    код = ВИМІР.replace("КОЛІР", колір).replace("КАДР", кадр).replace("ВЛАСНИК", власник)
    if "після" not in власник:          # запис без власника: і кадр виміру власника не несе
        код = код.replace('    після["власник_кадру"] = доказ["варіант"] if доказ else "невідомо"\n', "")
    return [м.статус for м in місця(код) if м.ключ == "колір_основний"]


class УточненняКласу(unittest.TestCase):
    """Колір кадру з доведеним власником — не місце п.2; запис доказу власності — не місце п.1 (13.11)."""

    def test_колір_доведеного_кадру(self):
        """Колір пишеться лише з доказом, запис несе власника, кадр виміру — з маніфестом (`sha256`)."""
        self.assertEqual(колір_виміру(), ["дотримує"])
        self.assertEqual(колір_виміру('основний if доказ else dict(колір_тип="невідомо")'), ["дотримує"])
        self.assertEqual(колір_виміру("None if доказ is None else основний"), ["дотримує"])

    def test_колір_без_доказу(self):
        """Той самий запис кольору, що пишеться й без доведеного власника (гілка «невідомо»), — місце."""
        self.assertEqual(колір_виміру("основний"), ["порушує"])
        self.assertEqual(колір_виміру("основний if not доказ else None"), ["порушує"])

    def test_колір_без_власника_чи_маніфесту(self):
        """Без власника в записі чи з кадром виміру лише адресою — місце, хоч колір і під доказом."""
        self.assertEqual(колір_виміру(власник='"невідомо"'), ["порушує"])
        self.assertEqual(колір_виміру(кадр='фото["url"]'), ["порушує"])

    def test_колір_гілкою_доказу(self):
        """Оператор `if доказ:` — колір під доказом; гілка без доказу кольору варіанта не пише."""
        код = ВИМІР.replace("    return dict(", "    if ДОКАЗ:\n        return dict(").replace(
            "КОЛІР", "основний").replace("КАДР", "після").replace("ВЛАСНИК", 'після["власник_кадру"]')
        self.assertEqual([м.статус for м in місця(код.replace("ДОКАЗ", "доказ")) if м.ключ == "колір_основний"],
                         ["дотримує"])
        self.assertEqual([м.статус for м in місця(код.replace("ДОКАЗ", "not доказ")) if м.ключ == "колір_основний"],
                         ["порушує"])

    def test_запис_доказу(self):
        """Власник із даних крамниці, кадр — ключ звірки з прив'язкою платформи: точка, де власник з'являється."""
        self.assertEqual([м.статус for м in місця(ДОКАЗ_ЗАПИСУ) if м.ключ == "кадр"], ["дотримує"])

    def test_варіант_поруч_не_доказ(self):
        """Поле варіанта поруч із першим кадром галереї власника кадру не доводить."""
        код = '''
def читати(html):
    дані = json.loads(html)
    return dict(варіант=дані["variant"], кадр=дані["images"][0])
'''
        self.assertEqual([м.статус for м in місця(код) if м.ключ == "кадр"], ["порушує"])

    def test_копія_запису(self):
        """Копія вже записаного поля того самого запису — похідне; без запису вище — ні."""
        код = '''
def накласти(r, html):
    r["lab"] = поверхня_фото(html)
    r["colors"] = [dict(lab=_КР.точка_кольору(r))]
'''
        self.assertEqual([м.статус for м in місця(код) if м.ключ == "lab" and м.рядок == 4], ["поза класом"])
        без = код.replace('    r["lab"] = поверхня_фото(html)\n', "")
        self.assertNotEqual([м.статус for м in місця(без) if м.ключ == "lab"], ["поза класом"])


