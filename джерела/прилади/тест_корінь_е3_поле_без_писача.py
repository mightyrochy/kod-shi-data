def прогін(дерево):
    with tempfile.TemporaryDirectory() as т:
        for шлях, текст in дерево.items():
            повний = os.path.join(т, "джерела", шлях)
            os.makedirs(os.path.dirname(повний), exist_ok=True)
            with open(повний, "w", encoding="utf-8") as ф:
                ф.write(текст)
        р = запустити_python([sys.executable, ПРИЛАД, "--корінь", т, "--json"], capture_output=True, text=True,
                           timeout=300)
        assert р.returncode == 0, р.stderr
        return json.loads(р.stdout[:р.stdout.rindex("місць:")])


class ПолеБезПисача(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.р = прогін(ДЕРЕВО)
        cls.місця = {(м["поле"], м["пункт"]) for м in cls.р["місця"]}

    def test_п1_без_писача(self):
        """`господар` приходить лише з `**сценарію`, ніхто його не пише — місце п.1."""
        self.assertIn(("господар", 1), self.місця)

    def test_писачі_не_місця(self):
        """`місце` пише показ, `дощ` — код у носій сценарію."""
        поля = {п for п, _ in self.місця}
        self.assertNotIn("місце", поля)
        self.assertNotIn("дощ", поля)

    def test_п2_літерал_поза_писачем(self):
        """Паспорт пише `мета="лестити"`, гілка чекає `"приховати"` — місце п.2."""
        self.assertIn(("мета", 2), self.місця)

    def test_опція_виклику_ui_не_писач(self):
        """`фокус` — ключ опцій `відкритиАркуш(…, {фокус: …})` у `показ/екран/`: ід поля для курсора, нічого не пише у
        вхід, тож Python-читач `фокус` — місце п.1; `підказка` у тілі запиту мосту — писач, не місце."""
        self.assertIn(("фокус", 1), self.місця)
        self.assertNotIn("підказка", {п for п, _ in self.місця})

    def test_ключ_стану_екрана_не_писач(self):
        """`кнопка` — ключ вкладеного літерала `Екран.змінити({аркуш: {кнопка: …}})`: `змінити` перебирає ключі аргументу
        й кладе їх у стан екрана, у сценарій нічого не пише, — однойменний ключ іншого об'єкта, тож Python-читач
        `кнопка` — місце п.1 (15386)."""
        self.assertIn(("кнопка", 1), self.місця)

    def test_причини_не_місць_є_на_main(self):
        # кожне не-місце справжнього дерева має причину поіменно; ключ без причини — «БЕЗ ПРИЧИНИ» і код 1
        р = запустити_python([sys.executable, ПРИЛАД, "--тихо"], capture_output=True, text=True,
                           cwd=os.path.join(os.path.dirname(ПРИЛАД), "..", ".."))
        self.assertEqual(р.returncode, 0, р.stderr)
        self.assertNotIn("БЕЗ ПРИЧИНИ", р.stderr)

    def test_не_місця_класу(self):
        """`ЗОВНІШНІ_ВХОДИ` чекліста, читач, що сам каже «входу нема», і параметр стенда — не місця."""
        поля = {п for п, _ in self.місця}
        self.assertNotIn("тренд_сезону", поля)
        self.assertNotIn("гардероб", поля)
        self.assertNotIn("шлях_фіду", поля)
        self.assertIn("гардероб", {к for _, _, к, _ in self.р["сам_каже"]})
        self.assertIn("шлях_фіду", self.р["не_поле"])


if __name__ == "__main__":
    unittest.main()
