def _рядок_ключа(текст, ключ, від=0):
    і = текст.find('"%s"' % ключ, від)
    return (текст.count("\n", 0, і) + 1 if і >= 0 else 0), max(і, 0)


def конфіг(корінь):
    вихід = []
    for ф in КОНФІГ:
        шлях = os.path.join(корінь, ф)
        if not os.path.exists(шлях):
            ОБСЯГ.непрочитано(ф, "конфігу нема на дереві")
            continue
        текст = читати(шлях, "utf-8-sig")
        try:
            док = json.loads(текст)
        except ValueError as е:
            ОБСЯГ.непрочитано(ф, "JSON: %s" % е)
            continue

        def додати(імя, значення, джерело, рядок):
            hang = bool(_HANG.search(імя))
            вимір = bool(_ВИМІР_ДАТА.search(джерело or ""))
            вихід.append(Одиниця("конфіг", ф, рядок, "конфіг|%s|%s" % (ф, імя), "%s = %s" % (імя, значення),
                                 (джерело or "")[:160], джерело=bool((джерело or "").strip()), hang=hang,
                                 вимір=вимір, слот=імя.startswith("slots.")))

        for к, в in док.items():
            if к == "v":
                continue
            if isinstance(в, (int, float)) and not isinstance(в, bool):
                додати(к, в, None, _рядок_ключа(текст, к)[0])
            elif isinstance(в, dict) and "n" in в:
                додати(к, в["n"], в.get("джерело", ""), _рядок_ключа(текст, к)[0])
            elif isinstance(в, dict):
                рядок, від = _рядок_ключа(текст, к)
                for к2, в2 in в.items():
                    if isinstance(в2, dict) and "n" in в2:
                        додати("%s.%s" % (к, к2), в2["n"], в2.get("джерело", ""), _рядок_ключа(текст, к2, від)[0])
                    elif isinstance(в2, (int, float)) and not isinstance(в2, bool):
                        додати("%s.%s" % (к, к2), в2, None, _рядок_ключа(текст, к2, від)[0])
    return вихід


