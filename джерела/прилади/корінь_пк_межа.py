def норм(текст):
    """Нормований текст пункту: без розмітки, номерів рядків у посиланнях і зайвих пробілів, малими."""
    т = текст.lower().replace("`", "").replace("*", "")
    т = re.sub(r":\d+(?:\s*[–-]\s*\d+)?", ":N", т)
    return re.sub(r"\s+", " ", т).strip()


def читати(шлях, кодування="utf-8"):
    with open(шлях, encoding=кодування) as ф:
        return ф.read()


def хеш(текст):
    return hashlib.sha1(норм(текст).encode("utf-8")).hexdigest()[:12]


