def _не_одиниця(число):
    return re.fullmatch(r"[01](?:\.0+)?", число) is not None


def _код_і_коментар(рядок):
    """(код, коментар) рядка: `#` поза лапками відтинає коментар."""
    лапка = None
    for і, с in enumerate(рядок):
        if лапка:
            if с == лапка:
                лапка = None
            elif с == "`" and лапка == '"':
                continue
        elif с in "'\"":
            лапка = с
        elif с == "#" and (і == 0 or рядок[і - 1] in " \t;"):
            return рядок[:і], рядок[і + 1:]
    return рядок, ""


def _дужки(код):
    """Різниця `{`−`}` поза лапками."""
    лапка, р = None, 0
    for с in код:
        if лапка:
            if с == лапка:
                лапка = None
        elif с in "'\"":
            лапка = с
        elif с == "{":
            р += 1
        elif с == "}":
            р -= 1
    return р


def _рядки_коду(текст):
    """[(номер, код, коментар, коментар_над)] без блок-коментарів `<# #>` і here-рядків `@' '@`."""
    вихід, над, блок, тут = [], [], False, None
    for н, рядок in enumerate(текст.lstrip("﻿").split("\n"), 1):
        р = рядок.rstrip("\r")
        с = р.strip()
        if тут:
            if с.startswith(тут):
                тут = None
            continue
        if блок:
            над.append(с)
            if "#>" in с:
                блок = False
            continue
        if с.startswith("<#"):
            над.append(с)
            блок = "#>" not in с[2:]
            continue
        if с.startswith("#"):
            над.append(с)
            continue
        код, коментар = _код_і_коментар(р)
        код = re.sub(r"<#.*?#>", "", код)
        if re.search(r"@['\"]\s*$", код):
            тут = код.rstrip()[-1] + "@"
        вихід.append((н, код, коментар, " ".join(над)))
        if с:
            над = []
    return вихід


def код(корінь, поля, лінії):
    вихід = []
    файли = sorted(glob.glob(os.path.join(корінь, КОД)))
    звязки = {}
    тексти = {}
    for шлях in файли:
        т = читати(шлях, "utf-8-sig")
        тексти[шлях] = т
        for м in re.finditer(r"Get-Limit\s+\$[\w:]+\s+'(\w+)'\s+'(\w+)'", т):
            звязки[м.group(1)] = м.group(2)
        for м in re.finditer(r"ContainsKey\('(\w+)'\)\)\s*\{\s*\$(?:script:)?\1\s*=\s*(?:\[\w+\])?\$\w+\['(\w+)'\]", т):
            звязки[м.group(1)] = м.group(2)
    for шлях in файли:
        ф = os.path.relpath(шлях, корінь).replace(os.sep, "/")
        рядки = _рядки_коду(тексти[шлях])
        глибина, функції, лік = 0, [], {}  # функції: [імя, глибина оголошення, тіло відкрито]

        def поточна():
            return функції[-1][0] if функції else "скрипт"

        def додати(н, вид, імя, число, уривок, джерело_т, п4=False, сталий_ключ=None):
            if сталий_ключ:
                ключ = "код|%s|%s" % (ф, сталий_ключ)
            else:
                основа = (ф, поточна(), норм(уривок), число)
                лік[основа] = лік.get(основа, 0) + 1
                ключ = "код|%s|%s|%s|%s|%d" % (ф, поточна(), хеш(уривок), число, лік[основа])
            вихід.append(Одиниця("код", ф, н, ключ, "%s %s" % (імя, число), уривок.strip()[:160],
                                 джерело=bool(_ДЖЕРЕЛО_КОД.search(джерело_т)), п4=п4,
                                 hang=bool(_HANG.search(імя)), вимір=bool(_ВИМІР_ДАТА.search(джерело_т))))

        і = 0
        while і < len(рядки):
            н, к, коментар, над = рядки[і]
            джерело_т = над + " " + коментар
            мф = re.match(r"\s*function\s+([\w-]+)", к)
            if мф:
                функції.append([мф.group(1), глибина, False])
            # сталі скрипта (глибина 0): число чи хеш-таблиця чисел
            мс = _СТАЛА.match(к) if глибина == 0 else None
            if мс:
                імя, праве = мс.group(1), мс.group(2).strip()
                if re.fullmatch(_ЧИСЛО, праве):
                    if not _не_одиниця(праве):
                        додати(н, "стала", імя, праве, к, джерело_т, сталий_ключ="стала|" + імя)
                    і += 1
                    continue
                мт = re.match(r"(?:\[ordered\])?@\{", праве)
                if мт:
                    тіло, j, г = [(н, праве[мт.end():], джерело_т)], і, _дужки(праве)
                    while г > 0 and j + 1 < len(рядки):
                        j += 1
                        тіло.append((рядки[j][0], рядки[j][1], рядки[j][3] + " " + рядки[j][2]))
                        г += _дужки(рядки[j][1])
                    for нн, кк, дж in тіло:
                        for мз in _ЗАПИС.finditer(кк):
                            ключ_з, значення = мз.group(1), re.sub(r"\s+", "", мз.group(2))
                            if not значення.startswith("@") and _не_одиниця(значення):
                                continue
                            п4 = ключ_з in поля or ключ_з in лінії or (імя == "Ceil" and ключ_з == "slots")
                            додати(нн, "запис", "%s.%s" % (імя, ключ_з), значення, кк, джерело_т + " " + дж,
                                   п4=п4, сталий_ключ="запис|%s.%s" % (імя, ключ_з))
                    і = j + 1
                    continue
            # параметри з числом за замовчуванням (скрипта й функцій)
            for мп in _ПАРАМЕТР.finditer(к):
                імя, число = мп.group(1), мп.group(2)
                if _не_одиниця(число):
                    continue
                додати(н, "параметр", імя, число, к, джерело_т, п4=звязки.get(імя) in поля,
                       сталий_ключ="параметр|%s|%s" % (поточна(), імя))
            # межові звороти в тілі
            for вид, рег in _ВБУДОВАНІ:
                for мв in рег.finditer(к):
                    число = next(г for г in мв.groups() if г)
                    if _не_одиниця(число):
                        continue
                    if вид == "аргумент" and _ПАРАМЕТР.search(к[max(0, мв.start() - 20):мв.end() + 1]):
                        continue
                    додати(н, вид, вид, число, к, джерело_т)
            # гілка «без джерела — попереднє чи типове»: пише поле в unsourced і все одно присвоює значення
            if re.search(r"unsourced\s*\+=", к):
                блок = " ".join(р[1] for р in рядки[і:і + 4])
                if re.search(r"unsourced\s*\+=[^}]*\$\w+\s*=", блок):
                    додати(н, "гілка", "без джерела — попереднє", "гілка", к, джерело_т, п4=True,
                           сталий_ключ="гілка|%s|unsourced" % поточна())
            д = _дужки(к)
            if функції and not функції[-1][2] and "{" in к:
                функції[-1][2] = True
            глибина += д
            while функції and функції[-1][2] and глибина <= функції[-1][1]:
                функції.pop()
            і += 1
    return вихід


