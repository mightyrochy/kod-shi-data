def _пункти(текст):
    """Пункт: рядок таблиці, пункт списку з продовженням, абзац (як `приховані_g_межі.py`)."""
    пункт, поч = [], 0
    for н, рядок in enumerate(текст.split("\n"), 1):
        новий = (not рядок.strip() or рядок.lstrip().startswith(("- ", "* ", "|", "#"))
                 or re.match(r"\s*\d+\.\s", рядок))
        if новий and пункт:
            yield поч, " ".join(пункт)
            пункт = []
        if рядок.strip():
            if not пункт:
                поч = н
            пункт.append(рядок.strip())
            if рядок.lstrip().startswith(("|", "#")):
                yield поч, " ".join(пункт)
                пункт = []
    if пункт:
        yield поч, " ".join(пункт)


def одиниці_пункту(ф, пункт):
    """[(збіг, ключ, k першої регулярки чи 0)] пункту в порядку тексту; k — номер збігу `приховані_g_межі.py`."""
    перші = [м for м in _МЕЖА.finditer(пункт)
             if not re.match(r"\d+\s*%", м.group(0)) or "ліміт" in пункт or "квот" in пункт]
    зайняті = [(м.start(), м.end()) for м in перші]
    другі = [м for м in _ДОДАТКОВА.finditer(пункт)
             if not any(м.start() < к and п < м.end() for п, к in зайняті)]
    номер = {id(м): к for к, м in enumerate(перші, 1)}
    х, лік, вихід = хеш(пункт), {}, []
    for м in sorted(перші + другі, key=lambda м: м.start()):
        з = норм(м.group(0))
        лік[з] = лік.get(з, 0) + 1
        вихід.append((м, "правило|%s|%s|%s|%d" % (ф, х, з, лік[з]), номер.get(id(м), 0)))
    return вихід


def правила(корінь):
    вихід = []
    for ф in ПРАВИЛА:
        шлях = os.path.join(корінь, ф)
        if not os.path.exists(шлях):
            ОБСЯГ.непрочитано(ф, "файлу правил нема на дереві")
            continue
        for н, пункт in _пункти(читати(шлях)):
            if пункт.startswith("#") or re.match(r"\|[\s|:-]+\|?$", пункт):
                continue
            збіги = одиниці_пункту(ф, пункт)
            if not збіги:
                continue
            є = bool(_ДЖЕРЕЛО.search(пункт))
            вимір = bool(_ВИМІР_ДАТА.search(пункт))
            for м, ключ, _ in збіги:
                вікно = пункт[max(0, м.start() - 60):м.end() + 60]
                вихід.append(Одиниця("правила", ф, н, ключ, м.group(0), вікно, джерело=є,
                                     hang=bool(_HANG.search(вікно)), вимір=вимір))
    return вихід


