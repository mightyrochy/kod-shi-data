def вердикти(корінь):
    шлях = os.path.join(корінь, ВЕРДИКТИ)
    вихід = {}
    if not os.path.exists(шлях):
        ОБСЯГ.непрочитано(ВЕРДИКТИ, "вердиктів нема на дереві")
        return вихід
    for рядок in читати(шлях).split("\n"):
        if not рядок.strip() or рядок.startswith("#"):
            continue
        поля = рядок.rstrip("\n").split("\t")
        if len(поля) >= 2 and поля[1].strip() in НЕ_МІСЦЕ | set(ПУНКТ_ВЕРДИКТУ):
            вихід[поля[0].strip()] = поля[1].strip()
    return вихід


def вирішити(о, в):
    """Стан одиниці: 0 — не місце, 1–4 — пункт класу (порядок правил — у шапці)."""
    о.вердикт = в.get(о.ключ, "")
    if о.п4:
        return 4
    if о.вердикт in ("НМ", "ДУБЛЬ"):
        return 0
    if (о.hang or о.слот) and о.вимір:
        return 0  # рішення менеджера 31.10: HANG/STALL і слоти з поміткою виміру з датою — не місце
    if о.вердикт in ("МС", "МВ"):
        return 0 if not о.hang else 2  # HANG/STALL без помітки виміру — місце, хоч би який вердикт
    if о.вердикт in ПУНКТ_ВЕРДИКТУ:
        return ПУНКТ_ВЕРДИКТУ[о.вердикт]
    return 2 if о.джерело else 1


def зібрати(корінь):
    поля, лінії = поля_смуг(корінь)
    усі = правила(корінь) + конфіг(корінь) + код(корінь, поля, лінії)
    в = вердикти(корінь)
    for о in усі:
        о.пункт = вирішити(о, в)
    return усі, в


