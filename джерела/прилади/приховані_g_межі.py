# -*- coding: utf-8 -*-
"""Межі роботи без джерела в правилах роботи — частина (ґ) розвідки «Приховані».

Ядро (`AGENTS.md`, «Межа роботи», власник 29.10): «темп, слоти, очікування, стоп — лише з джерелом: слово власника з
датою чи вимір ресурсу (місце, пам'ять, квота); без джерела межі нема». Прилад знаходить у правилах роботи кожну
кількісну межу — частоту, стелю, строк, поріг чекання — і позначає, чи стоїть у тому самому пункті (абзаці чи пункті
списку, рядку таблиці) джерело: «власник» з датою, «вимір»/«урок»/«проба»/«ревізія»/«діагностика» з датою, число
виміру з датою «(77 з 86, 26.10)». Прилад не судить, чи межа потрібна, — лише лічить межі й частку без джерела.

Запуск з кореня репозиторію:
  python3 джерела/прилади/приховані_g_межі.py            лічба: межі, з джерелом, без джерела — за файлами
  python3 джерела/прилади/приховані_g_межі.py --усі      ід ⇥ джерело(так/ні) ⇥ місце ⇥ межа ⇥ уривок
  python3 джерела/прилади/приховані_g_межі.py --перелік аудит/корені/Приховані-перелік-ґ.md
      покриття: знахідка покрита, коли її ід стоїть першою клітинкою рядка таблиці переліку (`| ґм:… | … |`).
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from приховані_g_обсяг import КОРІНЬ, ПРАВИЛА_РОБОТИ  # noqa: E402

# Кількісна межа роботи: частота, стеля, строк, поріг.
_МЕЖА = re.compile(
    r"раз на (?:\d+\s*)?(?:год|хв|добу|дві доби|тиждень|день|такт|групу|простій|вікно)\w*"
    r"|не частіше\b|не більше\b|не понад\b|щонайбільше|не менше\b"
    r"|щодоби|щогодини|щотижня"
    r"|кожн\w+ \d+\s*(?:год|хв)\w*"
    r"|\b\d+(?:[,.]\d+)?\s*(?:год|хв|сек|доб)\w*"
    r"|\b\d+\s*%"
    r"|\bдо \d+\b|\bстел\w+|\bліміт\w*|\bслот\w*|\bтайм-?аут\w*|\bстрок\w*", re.I)
_ДЖЕРЕЛО = re.compile(
    r"власник\w*[^()]{0,40}?\d{1,2}\.(?:09|10|11)"
    r"|(?:вимір|урок|проба|ревізі\w*|діагностик\w*|замір|слово)[^()]{0,40}?\d{1,2}\.(?:09|10|11)"
    r"|\d+\s*з\s*\d+[^()]{0,30}\d{1,2}\.(?:09|10|11)"
    r"|\(\d{1,2}\.(?:09|10|11)\b", re.I)


def _пункти(текст):
    """Пункт: рядок таблиці, пункт списку з продовженням, абзац. Дає (номер першого рядка, текст)."""
    пункт, поч = [], 0
    for н, рядок in enumerate(текст.split("\n"), 1):
        новий = (not рядок.strip() or рядок.lstrip().startswith(("- ", "* ", "|", "#"))
                 or re.match(r"\s*\d+\.\s", рядок))
        if новий and пункт:
            yield поч, " ".join(пункт)
            пункт = []
        if рядок.strip():
            if not пункт:
                поч = н
            пункт.append(рядок.strip())
            if рядок.lstrip().startswith(("|", "#")):
                yield поч, " ".join(пункт)
                пункт = []
    if пункт:
        yield поч, " ".join(пункт)


def межі():
    вихід = []
    for ф in ПРАВИЛА_РОБОТИ:
        шлях = os.path.join(КОРІНЬ, ф)
        if not os.path.exists(шлях):
            continue
        for н, пункт in _пункти(open(шлях, encoding="utf-8").read()):
            if пункт.startswith("#") or re.match(r"\|[\s|:-]+\|?$", пункт):
                continue
            знайдені = [м for м in _МЕЖА.finditer(пункт)
                        if not re.match(r"\d+\s*%", м.group(0)) or "ліміт" in пункт or "квот" in пункт]
            if not знайдені:
                continue
            є = bool(_ДЖЕРЕЛО.search(пункт))
            for к, м in enumerate(знайдені, 1):
                вихід.append(("ґм:%s:%d.%d" % (ф, н, к), "так" if є else "ні", "%s:%d" % (ф, н), м.group(0),
                              пункт[max(0, м.start() - 70):м.end() + 70]))
    return вихід


def main():
    п = argparse.ArgumentParser()
    п.add_argument("--усі", action="store_true")
    п.add_argument("--перелік")
    а = п.parse_args()
    усі = межі()
    if а.усі:
        for о in усі:
            print("\t".join(о))
        return
    за = {}
    for о in усі:
        ф = о[2].rsplit(":", 1)[0]
        за.setdefault(ф, [0, 0])[0 if о[1] == "так" else 1] += 1
    for ф, (т, н) in за.items():
        print("%-45s з джерелом %3d, без %3d" % (ф, т, н))
    т = sum(в[0] for в in за.values())
    н = sum(в[1] for в in за.values())
    print("усього меж %d: з джерелом у пункті %d, без джерела %d" % (т + н, т, н))
    if а.перелік:
        покрито = покриті(а.перелік, "ґм:")
        є = sum(1 for о in усі if о[0] in покрито)
        print("з вердиктом %d з %d (%.0f %%)" % (є, len(усі), 100.0 * є / max(1, len(усі))))
        зайві = sorted(покрито - {о[0] for о in усі})
        if зайві:
            print("ід переліку без знахідки (зсув рядків?): %d — %s" % (len(зайві), ", ".join(зайві[:8])))


def покриті(перелік, префікс):
    """Ід із першої клітинки рядків таблиці переліку з цим префіксом."""
    вихід = set()
    for рядок in open(os.path.join(КОРІНЬ, перелік), encoding="utf-8"):
        м = re.match(r"\|\s*`?(%s[^|`]+?)`?\s*\|" % re.escape(префікс), рядок)
        if м:
            вихід.add(м.group(1))
    return вихід


if __name__ == "__main__":
    main()
