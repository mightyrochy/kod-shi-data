# -*- coding: utf-8 -*-
"""ГІЛКИ НЕЗЛИТІ (рядок 131 дошки): звіт, які `origin/*` гілки, крім `main`,
несуть власний вміст, якого нема в `main`, і чи він ДОСІ відрізняється зараз.

ЧОМУ. 22.09 власник знайшов незлиту роботу раніше за куратора — перевірка
куратора мала три діри: (1) бачила лише сесії, роздані нею самою; (2) питала
лише «чи є ФАЙЛ, якого нема в main», а змінений вміст у спільних файлах не
ловила; (3) `git log --name-only` віддає кириличні шляхи ЕКРАНОВАНИМИ
(`"\\320\\264…"`), такий рядок не збігається з реальним — і скрипт мовчав.
Тут: (2) лагодиться порівнянням ВМІСТУ (`git diff --name-only` між повними
деревами гілки й main, не лише списком файлів коміту), (3) — прапорцем
`core.quotepath=false` на КОЖНОМУ виклику git. (1) лагодить лише
опційний `--сесії`: цей прилад сам API сесій не кличе.

ЧЕТВЕРТА ДІРА (знайдена куратором на PR #222, мілкий клон хмарної сесії,
глибина 50). `git cherry origin/main <гілка>` без спільного предка в
отриманій історії малює «+» на ВСІ коміти гілки — стара гілка виглядає
цілком «своєю», хоча насправді судити її просто нема чим. Лагодиться
`git merge-base` ПЕРЕД `cherry`: порожній результат — окремий третій клас
«не можу судити» (мілкий клон або справді окрема історія), а не «незлита
робота». `--is-shallow-repository` друкується як попередження на початку.

Лише читає git, нічого не пише. Код виходу — завжди 0: це звіт, не гейт
(п.3 CLAUDE.md) — класифікація гілок нічого не «валить».

Прогін:  python3 прилади/гілки_незлиті.py [--сесії файл.json] [--гілки а,б] [--json]
"""
import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone

ГОЛОВНА = "origin/main"
_КОРІНЬ = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True,
                          encoding="utf-8", check=True).stdout.strip()


def git(*аргументи):
    """Один виклик git з `core.quotepath=false`, завжди з коренем репо як cwd:
    шляхи від `diff --name-only`/`diff-tree` репо-кореневі, і `-- шлях` мусить
    ним же й читатись — інакше запуск із теки `джерела/` мовчки не знаходить
    файл (той самий клас поломки, що екрановані шляхи рядка 130)."""
    п = subprocess.run(["git", "-c", "core.quotepath=false", *аргументи], cwd=_КОРІНЬ,
                        capture_output=True, text=True, encoding="utf-8")
    if п.returncode != 0:
        raise RuntimeError("git %s: %s" % (" ".join(аргументи), п.stderr.strip()))
    return п.stdout


def мілкий_клон():
    return git("rev-parse", "--is-shallow-repository").strip() == "true"


def гілки_на_огляд(фільтр=None):
    """Усі `origin/*`, крім `origin/HEAD` (символічне посилання) і `origin/main`;
    `фільтр` (короткі або повні імена) звужує список для швидкого/цільового прогону."""
    рядки = [р.strip() for р in git("branch", "-r").splitlines() if р.strip()]
    усі = sorted(р for р in рядки if "->" not in р and р != ГОЛОВНА)
    if фільтр is None:
        return усі
    бажані = set(фільтр)
    return [р for р in усі if р in бажані or р[len("origin/"):] in бажані]


def спільний_предок(гілка):
    """Порожньо — спільного предка з `main` нема в ОТРИМАНІЙ історії: `git cherry`
    без нього ненадійний (малює «+» на все), і клас гілки визначає не він."""
    п = subprocess.run(["git", "-c", "core.quotepath=false", "merge-base", ГОЛОВНА, гілка],
                        cwd=_КОРІНЬ, capture_output=True, text=True, encoding="utf-8")
    if п.returncode not in (0, 1):
        raise RuntimeError("git merge-base %s: %s" % (гілка, п.stderr.strip()))
    return п.stdout.strip() or None


def власні_коміти(гілка):
    """`+`-рядки `git cherry` — коміти гілки, яких main не має і не поглинув еквівалентом."""
    return [р.split()[1] for р in git("cherry", ГОЛОВНА, гілка).splitlines() if р.startswith("+")]


def дати_і_файли_комітів(коміти):
    """Одним викликом (не N): дата кожного коміту, і файл → найпізніша дата ВЛАСНОГО
    коміту, що його торкнувся. `--no-walk` — щоб `git log` показав РІВНО ці коміти,
    а не всю історію, досяжну з них; `diff-tree` тут не годиться, бо він трактує рівно
    2 SHA-аргументи як «дерево A проти дерева B», а 3+ — як шлях-обмеження діапазону
    двох перших (перевірено: порожній вивід на будь-якій кількості SHA, крім 1)."""
    вивід = git("log", "--no-walk", "--name-only", "--format=@@%H%x09%cI", *коміти)
    дата_коміту, дата_файла = {}, {}
    поточний = None
    for р in вивід.splitlines():
        if р.startswith("@@"):
            sha, _, дата = р[2:].partition("\t")
            дата_коміту[sha] = дата
            поточний = дата
        elif р:
            if поточний and (р not in дата_файла or поточний > дата_файла[р]):
                дата_файла[р] = поточний
    return дата_коміту, дата_файла


def файли_що_відрізняються(гілка):
    """Повний список файлів, де ВМІСТ гілки і `main` зараз різний (не лише наявність)."""
    return set(р for р in git("diff", "--name-only", ГОЛОВНА, гілка).splitlines() if р)


def дата_main_на_шляху(шлях):
    """Дата останнього коміту `main`, що торкнувся цього шляху; порожньо — main його не мав."""
    вивід = git("log", "-1", "--format=%cI", ГОЛОВНА, "--", шлях).strip()
    return вивід or None


def сесія_для(гілка, сесії):
    if not сесії:
        return None
    без_префікса = гілка[len("origin/"):]
    короткий = без_префікса.rsplit("/", 1)[-1]
    return сесії.get(без_префікса) or сесії.get(короткий) or сесії.get(гілка)


def проаналізувати(гілка, тепер, мілкий=None):
    if спільний_предок(гілка) is None:
        причина = "нема спільного предка з main в отриманій історії — " + (
            "мілкий клон" if (мілкий if мілкий is not None else мілкий_клон()) else "окрема історія")
        коміти_за_cherry = власні_коміти(гілка)  # лише для інформації — судити ними не можна
        return dict(гілка=гілка, клас="не_можу_судити", причина=причина, комітів=len(коміти_за_cherry),
                    торкнуті_файли=[], відмінні_файли=[], переписані_main=[])
    коміти = власні_коміти(гілка)
    if not коміти:
        return dict(гілка=гілка, клас="без_вмісту", причина="усіх власних комітів нема (cherry порожній)",
                    комітів=0, торкнуті_файли=[], відмінні_файли=[], переписані_main=[])
    дата_коміту, дата_власного_дотику = дати_і_файли_комітів(коміти)
    остання_дата = max(дата_коміту.values())
    вік_днів = (тепер - datetime.fromisoformat(остання_дата)).days
    відмінні_усі = файли_що_відрізняються(гілка)
    свої_відмінні = sorted(set(дата_власного_дотику) & відмінні_усі)

    # СЕРЕД `своїх_відмінних` частина може бути НЕ незлитою роботою, а стосом,
    # який main переписав ПІЗНІШЕ (рядок 131: "усе вже в main або переписано
    # main пізніше" — другий клас). Різняться вмістом обидва, і чисте
    # порівняння файлів цього не розрізнить — тому звіряємо ДАТИ: якщо
    # останній дотик `main` до шляху пізніший за власний коміт гілки, це
    # `main` пішов далі, а не гілка лишилась попереду.
    попереду, переписані_main = [], []
    for ф in свої_відмінні:
        дата_main = дата_main_на_шляху(ф)
        if дата_main and дата_main > дата_власного_дотику[ф]:
            переписані_main.append(ф)
        else:
            попереду.append(ф)

    якщо_база = dict(комітів=len(коміти), остання_дата=остання_дата, вік_днів=вік_днів,
                      торкнуті_файли=sorted(дата_власного_дотику), переписані_main=переписані_main)
    if попереду:
        return dict(гілка=гілка, клас="незлита_робота", відмінні_файли=попереду, **якщо_база)
    причина = ("%d власних комітів, усі торкнуті файли вже збігаються з main" % len(коміти)
               if not свої_відмінні else
               "%d власних комітів, %d торкнутих файлів досі відрізняються, але `main` торкнувся їх ПІЗНІШЕ "
               "(переписав те саме після гілки)" % (len(коміти), len(переписані_main)))
    return dict(гілка=гілка, клас="без_вмісту", причина=причина, відмінні_файли=[], **якщо_база)


def надрукувати(результати, сесії, мілкий):
    if мілкий:
        print("!! КЛОН МІЛКИЙ (--is-shallow-repository): гілки без спільного предка в "
              "отриманій історії не судяться, а йдуть у «не можу судити». Поглибити: "
              "git fetch --unshallow (або --deepen=N).")
    незлиті = [р for р in результати if р["клас"] == "незлита_робота"]
    без_вмісту = [р for р in результати if р["клас"] == "без_вмісту"]
    не_судимо = [р for р in результати if р["клас"] == "не_можу_судити"]
    print("── незлита робота: %d гілок (з %d оглянутих)" % (len(незлиті), len(результати)))
    for р in sorted(незлиті, key=lambda x: -x["вік_днів"]):
        сесія = сесія_для(р["гілка"], сесії)
        хвіст = ""
        if сесії is not None:
            хвіст = "  сесія=%s" % (("%s статус=%s хто=%s" % (сесія["id"], сесія.get("статус", "?"),
                                     сесія.get("parent") or "власник")) if сесія else "нема")
        print("  %-55s вік %3d дн · комітів %2d · відмінних файлів %2d%s"
              % (р["гілка"][len("origin/"):], р["вік_днів"], р["комітів"], len(р["відмінні_файли"]), хвіст))
        for ф in р["відмінні_файли"]:
            print("      · %s" % ф)
    print("── без власного вмісту: %d гілок — %s"
          % (len(без_вмісту), ", ".join(р["гілка"][len("origin/"):] for р in без_вмісту) or "—"))
    print("── не можу судити (нема спільного предка): %d гілок — %s"
          % (len(не_судимо), ", ".join(р["гілка"][len("origin/"):] for р in не_судимо) or "—"))


def main():
    аргументи = argparse.ArgumentParser()
    аргументи.add_argument("--сесії", help="JSON {гілка: {id, parent, статус}} від куратора (list_sessions)")
    аргументи.add_argument("--гілки", help="звузити до цих гілок (короткі або повні імена, комою)")
    аргументи.add_argument("--json", action="store_true", help="вивід як JSON замість таблиці")
    нс = аргументи.parse_args()

    сесії = None
    if нс.сесії:
        сесії = json.load(open(нс.сесії, encoding="utf-8"))
    фільтр = [б.strip() for б in нс.гілки.split(",")] if нс.гілки else None

    мілкий = мілкий_клон()
    тепер = datetime.now(timezone.utc)
    результати = [проаналізувати(гілка, тепер, мілкий) for гілка in гілки_на_огляд(фільтр)]

    if нс.json:
        print(json.dumps(dict(створено=тепер.isoformat(), мілкий_клон=мілкий, гілок_оглянуто=len(результати),
                              результати=результати), ensure_ascii=False, indent=2))
    else:
        надрукувати(результати, сесії, мілкий)
    return 0


if __name__ == "__main__":
    sys.exit(main())
