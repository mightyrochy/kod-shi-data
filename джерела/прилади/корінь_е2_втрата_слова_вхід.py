def читання(тека=ТЕКА):
    """Таблиця читання: репліка → [рядки]; повертає (словник, помилки)."""
    файл = os.path.join(тека, 'читання.tsv')
    вих = collections.defaultdict(list)
    for р in csv.DictReader(_текст(файл).splitlines(), delimiter='\t'):
        if р['рівень'] not in ('пряме', 'виведене', 'поза_обсягом'):
            raise SystemExit('читання.tsv: невідомий рівень «%s» у репліці «%s»' % (р['рівень'], р['репліка'][:40]))
        вих[р['репліка']].append(р)
    return вих


