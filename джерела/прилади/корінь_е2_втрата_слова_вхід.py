def факти(рядки):
    """Кожен факт рішення: що прилад бачить у записах (стадія по проходах) чи чому не бачить."""
    вих = []
    for назва, сцена, поле, уривок in ФАКТИ:
        знайдені = [р for р in рядки if р['запис'][1].startswith(сцена) and р['поле'] == поле and уривок in р['уривок']]
        if not знайдені:
            вих.append('%s — НЕ БАЧИТЬ: у обсязі нема рядка лічби для сцени «%s*» і поля `%s`' % (назва, сцена, поле))
            continue
        по_стадіях = collections.Counter((р['запис'][0].split('-')[-1][:8], р['рівень'], р['стадія']) for р in знайдені)
        вих.append('%s — БАЧИТЬ: %s' % (назва, '; '.join('%s/%s → %s ×%d' % (*к, v) for к, v in sorted(по_стадіях.items()))))
    return вих


def підсумок_групи(зведення):
    """Числа групи записів: (назвала, дійшло, {стадія: кількість}); одиниця — сцена × поле (для списків — ще елемент)."""
    назвала = sum(len(з['назвала']) for з in зведення.values())
    дійшло = sum(len(з['дійшло']) for з in зведення.values())
    за_стадіями = {ст: sum(len(з['втрата'][ст]) for з in зведення.values()) for ст in СТАДІЇ}
    return назвала, дійшло, за_стадіями


def втрати_стадії(рядки, стадія):
    """Одиниці лічби (сцена × поле [× елемент]), чия перша невдала стадія — `стадія` (як у `згорнути`): список
    (прогін, сцена, репліка, поле, уривок, елемент)."""
    за_одиницями = collections.OrderedDict()
    for р in рядки:
        if р['рівень'] == 'виведене':
            continue
        прогін, сцена, прохід = р['запис']
        елемент = р['уривок'] if р['поле'] in СПИСКОВІ else None
        за_одиницями.setdefault((р['поле'], прогін, сцена, елемент), []).append((прохід, р['стадія'], р))
    вих = []
    for (поле, прогін, сцена, елемент), проходи in за_одиницями.items():
        невдалі = sorted(x for x in проходи if x[1] != 'дійшло')
        if невдалі and невдалі[0][1] == стадія:
            р = невдалі[0][2]
            вих.append((прогін, сцена, р['репліка'], поле, р['уривок'], елемент))
    return вих


