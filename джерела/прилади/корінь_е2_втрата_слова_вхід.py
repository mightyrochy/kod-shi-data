def об_єкт_за_ключем(текст, ключ):
    """Усі JSON-об'єкти, що стоять після `"<ключ>":` у тексті (дужки з урахуванням рядків)."""
    вих = []
    for m in re.finditer(r'"%s":\s*\{' % re.escape(ключ), текст):
        i, глибина, у_рядку, екран = m.end() - 1, 0, False, False
        for j in range(i, len(текст)):
            c = текст[j]
            if у_рядку:
                if екран:
                    екран = False
                elif c == '\\':
                    екран = True
                elif c == '"':
                    у_рядку = False
            elif c == '"':
                у_рядку = True
            elif c == '{':
                глибина += 1
            elif c == '}':
                глибина -= 1
                if глибина == 0:
                    try:
                        вих.append(json.loads(текст[i:j + 1]))
                    except ValueError:
                        pass
                    break
    return вих


def схема_з_промпта(текст):
    """Поля схеми відповіді мовної моделі: рядки `- <поле> — …` розділу `codes` і перелік `about` (імена латиницею)."""
    поля = set(re.findall(r'"- ([a-z_]+) — ', текст))
    for m in re.finditer(r'update field codes \(([^)]*)\)', текст):
        поля.update(x.strip() for x in m.group(1).split(',') if re.fullmatch(r'[a-z_]+', x.strip()))
    return поля


def відповідь_update(текст):
    """`update` з відповіді моделі (JSON, можливо в ```-огорожі); немає — {}."""
    m = re.search(r'```json\s*(.*?)```', текст, re.S)
    сире = m.group(1) if m else текст
    try:
        об = json.loads(сире)
    except ValueError:
        i = сире.find('{')
        try:
            об = json.loads(сире[i:]) if i >= 0 else {}
        except ValueError:
            return {}
    return об.get('update') if isinstance(об, dict) and isinstance(об.get('update'), dict) else {}


def перша_репліка(текст):
    m = re.search(r'"her_new_message":\s*("(?:[^"\\]|\\.)*")', текст)
    return json.loads(m.group(1)) if m else None


def _промпт_живий(рядок):
    пов = json.loads(рядок['запит'])['messages'][0]['content']
    return ''.join(ч.get('text', '') for ч in пов) if isinstance(пов, list) else str(пов)


def _відповідь_живий(рядок):
    return ''.join(ч.get('text', '') for ч in json.loads(рядок['відповідь']).get('content', []))


def розмова_з_обмінів(промпти, відповіді):
    """[(промпт, відповідь)] → ({репліка: [update…]}, схема, промпт_складання)."""
    оновлення, схема, складання = collections.defaultdict(list), set(), None
    for п, в in zip(промпти, відповіді):
        her = перша_репліка(п) if '"her_new_message"' in п else None
        if her is not None:
            оновлення[her].append(відповідь_update(в))
            схема |= схема_з_промпта(п)
        elif складання is None and '"case":{' in п.replace('"case": {', '"case":{') and '"day":' in п and '"outfits_wanted"' in п:
            складання = п
    return оновлення, схема, складання


def _розділи_промпта(п):
    """`case`, `day`, `person`, `her_items` промпта складання (словники або списки)."""
    вих = {}
    for ключ in ('case', 'day', 'person'):
        знайдено = об_єкт_за_ключем(п, ключ)
        вих[ключ] = знайдено[0] if знайдено else {}
    її = re.search(r'"her_items":\s*(\[.*?\]|\{)', п, re.S)
    вих['her_items'] = її.group(1) if її else ''
    return вих


def записи_живих(корінь=ПРОБИ):
    """Живі прогони «як людина» 2–4: записи розмов (сцена × прохід).

    Її репліки, паспорт, випадок моделі й діагноз сторінки — з `verdykty-*.json` (є в усіх трьох). Відповіді моделі
    (`update`) і промпт складання образів (`case`/`day`) — з `стенд/службове/<с>/обміни.jsonl.gz`, а він є лише в
    живого 4; де обмінів нема, `випадок_моделі` діагнозу — той самий `case`, що пішов стилістці, а відповідь моделі
    до розбору паспортом не записано (місце втрати «модель чи писач» не розрізняється)."""
    вих = []
    for номер in ЖИВІ:
        тека = os.path.join(корінь, 'живий-як-людина-%d' % номер)
        for файл in sorted(glob.glob(os.path.join(тека, '*', 'verdykty-*.json'))):
            сцена = os.path.basename(os.path.dirname(файл))
            д = _json(файл)
            обміни = os.path.join(тека, 'стенд', 'службове', сцена, 'обміни.jsonl.gz')
            рядки = [json.loads(р) for р in _рядки_gz(обміни)] if os.path.isfile(обміни) else []
            for і, прогін in enumerate(д['прогони']):
                свої = [р for р in рядки if str(р.get('прохід')) == str(і + 1)]
                оновлення, схема, складання = розмова_з_обмінів([_промпт_живий(р) for р in свої],
                                                                [_відповідь_живий(р) for р in свої])
                спільне = dict(д.get('спільне') or {}, **(прогін.get('спільне') or {}))
                репліки = [м['текст'] for м in (спільне.get('чат') or []) if м.get('хто') == 'людина']
                модель = (json.loads(свої[0]['запит']).get('model') if свої else None)
                з = _запис('живий-як-людина-%d' % номер, сцена, і + 1, модель, оновлення, схема, складання, спільне)
                з['репліки'] = репліки
                if not з['розділи']:
                    випадок = спільне.get('випадок_моделі')
                    випадок = json.loads(випадок) if isinstance(випадок, str) and випадок.strip().startswith('{') else (випадок or {})
                    з['розділи'] = {'case': випадок, 'day': {}, 'person': {}, 'her_items': ''}
                    з['розділи_з'] = 'випадок_моделі'
                вих.append(з)
    return вих


def записи_нічного(тека=НІЧНИЙ):
    """Нічний Е1-20261115: записи розмов (сцена, один прохід); діагноз сторінки — `вердикти.txt`, коли він є."""
    вих = []
    for сцена in sorted(os.listdir(тека)):
        v = os.path.join(тека, сцена, 'VIDPOVIDI')
        if not os.path.isdir(v):
            continue
        промпти, відповіді = [], []
        for файл in sorted(glob.glob(os.path.join(v, '*.txt'))):
            текст = _текст(файл)
            if '── ПРОМПТ' not in текст[:200]:
                continue
            п, _, в = текст.partition('── ВІДПОВІДЬ')
            промпти.append(п)
            відповіді.append(в)
        оновлення, схема, складання = розмова_з_обмінів(промпти, відповіді)
        спільне, модель = None, None
        діагноз = os.path.join(тека, сцена, 'вердикти.txt')
        if os.path.isfile(діагноз) and os.path.getsize(діагноз):
            д = _json(діагноз)
            спільне = dict(д.get('спільне') or {}, **((д.get('прогони') or [{}])[0].get('спільне') or {}))
            чат = [м for с in (спільне.get('чат') or []) for м in (с.get('мова_шару') or [])]
            модель = чат[0].get('модель') if чат else None
        з = _запис('Е1-нічний-живий-20261115', сцена, 1, модель, оновлення, схема, складання, спільне)
        з['репліки'] = list(оновлення)
        вих.append(з)
    return вих


def записи_gemini(тека=GEMINI):
    """Записи розмов прогону на моделях Gemini (`аудит/проби/живий-gemini-підписка-1/`; лише з прапорцем `--gemini`).

    Одиниця — сцена × прохід. Джерело — `<прогін>/стенд/службове/<сцена>/обміни.jsonl` (не стиснений; рядок — обмін
    сторінки з мостом: `запит`, `статус`, `відповідь`, той самий вигляд, що в живого 4): відповіді мовної моделі
    (`update`) і промпт складання образів (`case`/`day`). Паспорта й діагнозу сторінки (`verdykty-*.json`) у цих
    записах нема: діагноз для `no_input` — рядки `control · no_input=…` з `руки.jsonl` тієї ж сцени й проходу (діагноз
    поломки руки 2, не діагноз сторінки), паспорт — `None`. Прохід, де виклик мовної моделі не має відповіді 200, не
    виміряний (повертається другим значенням з причиною). Прогін — тека до `стенд` (`gemini-3.8-flash`,
    `спроба_5/вимір_с4`, …)."""
    вих, не_виміряно = [], []
    for файл in sorted(glob.glob(os.path.join(тека, '**', 'стенд', 'службове', '*', 'обміни.jsonl'), recursive=True)):
        сцена = os.path.basename(os.path.dirname(файл))
        прогін = os.path.relpath(файл, тека).split(os.sep + 'стенд' + os.sep)[0]
        рядки = [json.loads(р) for р in _текст(файл).splitlines() if р.strip()]
        діагнози = collections.defaultdict(list)
        руки = os.path.join(os.path.dirname(файл), 'руки.jsonl')
        if os.path.isfile(руки):
            for р in (json.loads(х) for х in _текст(руки).splitlines() if х.strip()):
                діагнози[р.get('прохід')] += [л for л in (р.get('поломка_руки_2') or {}).get('діагноз') or [] if 'no_input=' in л]
        for прохід in sorted({р['прохід'] for р in рядки}):
            свої = [р for р in рядки if р['прохід'] == прохід]
            чат = [р for р in свої if '"her_new_message"' in _промпт_живий(р)]
            вдалі = [р for р in свої if р.get('статус') == 200]
            оновлення, схема, складання = розмова_з_обмінів([_промпт_живий(р) for р in вдалі], [_відповідь_живий(р) for р in вдалі])
            ключ = (прогін, сцена, прохід)
            її = {перша_репліка(_промпт_живий(р)) for р in чат}
            if not чат or any(not оновлення.get(х) for х in її):
                не_виміряно.append((ключ, 'виклик мовної моделі на ході розмови без відповіді 200 (статуси: %s)' %
                                    ','.join(sorted({str(р.get('статус')) for р in чат}))))
                continue
            модель = json.loads(свої[0]['запит']).get('model')
            спільне = {'етапи': {'діагноз_прогону': діагнози.get(прохід, [])}}
            з = _запис(прогін, сцена, прохід, модель, оновлення, схема, складання, спільне)
            з['репліки'] = list(оновлення)
            з['паспорта_нема'] = True
            вих.append(з)
    return вих, не_виміряно


