def _текст(файл):
    with open(файл, encoding='utf-8') as ф:
        return ф.read()


def _json(файл):
    with open(файл, encoding='utf-8') as ф:
        return json.load(ф)


def _рядки_gz(файл):
    with gzip.open(файл, 'rt', encoding='utf-8') as ф:
        return ф.read().splitlines()


def порожнє(v):
    """Значення без змісту: None, '', 'unknown', 'невідомо', [], {} і словник лише з порожніх значень."""
    if isinstance(v, dict):
        if 'value' in v:
            return порожнє(v['value'])
        return all(порожнє(x) for x in v.values())
    if isinstance(v, (list, tuple)):
        return all(порожнє(x) for x in v)
    return v in ПУСТІ


# ───────────────────────── реєстри коду (AST) ─────────────────────────

def _літерал_словник(файл, назва, із_ключами_рядками=True):
    """Літерал словника верхнього рівня `назва = {…}` у файлі: лише пари «рядок: рядок» (решту, `**`, пропускає)."""
    дерево = ast.parse(_текст(файл))
    for вузол in дерево.body:
        цілі = вузол.targets if isinstance(вузол, ast.Assign) else ([вузол.target] if isinstance(вузол, ast.AnnAssign) else [])
        if any(isinstance(ц, ast.Name) and ц.id == назва for ц in цілі):
            вих = {}
            for к, з in zip(вузол.value.keys, вузол.value.values):
                if isinstance(к, ast.Constant) and isinstance(з, ast.Constant):
                    вих[к.value] = з.value
            return вих
    return {}


def реєстр_полів(корінь=КОРІНЬ):
    """Англійське поле схеми → {ключ паспорта, вимір}; ключ у `ПОЛЯ_ПАСПОРТА`, вимір — `вісь[0]`."""
    файл = os.path.join(корінь, 'джерела', 'паспорт_поля.py')
    дерево = ast.parse(_текст(файл))
    таблиця = {}
    for вузол in дерево.body:
        if isinstance(вузол, ast.Assign) and any(getattr(ц, 'id', '') == 'ПОЛЯ_ПАСПОРТА' for ц in вузол.targets):
            for к, з in zip(вузол.value.keys, вузол.value.values):
                if not (isinstance(к, ast.Constant) and isinstance(з, ast.Dict)):
                    continue
                властивості = {}
                for кк, зз in zip(з.keys, з.values):
                    if isinstance(кк, ast.Constant):
                        try:
                            властивості[кк.value] = ast.literal_eval(зз)
                        except (ValueError, SyntaxError):
                            pass
                ключ = к.value
                поле = властивості.get('поле')
                вісь = властивості.get('вісь')
                для_англ = [x for x in ((поле,) + (tuple(вісь) if isinstance(вісь, tuple) else ())) if x]
                for англ in для_англ:
                    запис = таблиця.setdefault(англ, {'ключ': None, 'вимір': None})
                    if not ключ.startswith('@') and not запис['ключ']:
                        запис['ключ'] = ключ
                    if isinstance(вісь, tuple) and вісь[0] == англ:
                        запис['вимір'] = англ
    return таблиця


def реєстр_стилістки(корінь=КОРІНЬ):
    """(`ПОЛЯ_ВИПАДКУ`: ключ паспорта → ключ `case`, `_ВИПАДОК_У_ДНІ`: ключ паспорта → ключ `day`)."""
    файл = os.path.join(корінь, 'джерела', 'дріт_моделі.py')
    return _літерал_словник(файл, 'ПОЛЯ_ВИПАДКУ'), _літерал_словник(файл, '_ВИПАДОК_У_ДНІ')


def входи_суду(корінь=КОРІНЬ):
    """Поля сценарію (імена паспорта), які правила суду читають як вхід: літерали `сценарій.<поле>[|<поле>]:` у `вхід`."""
    текст = _текст(os.path.join(корінь, 'джерела', 'поломки.py'))
    вих = set()
    for m in re.finditer(r'"сценарій\.([^":]+):', текст):
        вих.update(x for x in m.group(1).split('|') if x)
    return вих


