class Реєстри:
    """Реєстри коду, зведені до зручного вигляду (читаються з коду продукту, не з пам'яті лічильника)."""

    def __init__(self, корінь=КОРІНЬ):
        self.поля = реєстр_полів(корінь)
        self.у_випадку, self.у_дні = реєстр_стилістки(корінь)
        self.суд_укр = входи_суду(корінь)
        self.суд = {англ for англ, р in self.поля.items() if р['ключ'] in self.суд_укр}

    def ключ(self, поле):
        return (self.поля.get(поле) or {}).get('ключ')

    def вимір(self, поле):
        return (self.поля.get(поле) or {}).get('вимір')

    def ключі_стилістки(self, поле):
        """Ключі `case`/`day`, де стилістка може отримати поле: саме назва, ключ у `ПОЛЯ_ВИПАДКУ` й у `_ВИПАДОК_У_ДНІ`."""
        к = self.ключ(поле)
        return {поле, self.у_випадку.get(к), self.у_дні.get(к)} - {None}


def норма(текст):
    return json.dumps(текст, ensure_ascii=False).lower().replace('’', "'").replace('ʼ', "'")


def _листки(об):
    """Усі рядкові листки об'єкта (цитати моделі, значення, підписи)."""
    if isinstance(об, str):
        yield об
    elif isinstance(об, dict):
        for x in об.values():
            yield from _листки(x)
    elif isinstance(об, (list, tuple)):
        for x in об:
            yield from _листки(x)


def містить(об, уривок):
    """Чи стоїть її уривок (підрядок репліки) у переданому об'єкті: або сам уривок — підрядок його тексту, або якийсь
    його рядковий листок (цитата моделі) — підрядок уривка (довжиною від 5). Механічний збіг рядків, не пошук слів."""
    у = норма(уривок.strip().strip('«»"')).strip('"')
    if у in норма(об):
        return True
    return any(len(л) >= 5 and норма(л).strip('"') in у for л in _листки(об))


def в_паспорті(р, паспорт, поле, уривок=None):
    """Чи має паспорт поле: ключ паспорта непорожній або вимір не «unknown» з її слів чи тлумачення."""
    if not паспорт:
        return None
    if поле in СПИСКОВІ:
        к = р.ключ(поле)
        ключі = [к] + [x for x in ('слова', 'цитати_полів', 'картка_запиту', 'джерело_полів') if x != к]
        return any(not порожнє(паспорт.get(x)) and містить(паспорт.get(x), уривок) for x in ключі[:3]) if уривок else False
    к = р.ключ(поле)
    if к and not порожнє(паспорт.get(к)):
        return True
    в = р.вимір(поле)
    if в and not порожнє((паспорт.get('виміри') or {}).get(в)) and (паспорт.get('звідки') or {}).get(в) in ЇЇ_ЗВІДКИ:
        return True
    return False


def у_стилістки(р, розділи, поле, уривок=None):
    """Чи отримала стилістка поле: непорожнє значення в `case`/`day`/`person` (імена — із реєстрів коду)."""
    if not розділи:
        return None
    ключі = р.ключі_стилістки(поле)
    if поле in СПИСКОВІ and уривок:
        все = {розділ: розділи[розділ] for розділ in ('case', 'day', 'person')}
        все['her_items'] = розділи['her_items']
        return містить(все, уривок)
    for розділ in ('case', 'day', 'person'):
        для = розділи[розділ] or {}
        if any(к in для and not порожнє(для[к]) for к in ключі):
            return True
    if поле == 'own_items':
        її = розділи['her_items']
        return bool(її) and not порожнє(її.strip('[]{} \n'))
    return False


def стадія(р, запис, репліка, рядок, схема):
    """Місце втрати для рядка таблиці (поле, уривок) у записі; повертає (стадія, докази)."""
    поле = рядок['поле']
    докази = {}
    if поле in ДОДАТКОВІ_ПОЛЯ or поле not in (запис['схема'] or схема):
        return 'схема', {'у_схемі': False}
    оновлення = запис['оновлення'].get(репліка)
    if not запис['оновлення']:
        написала = None
    elif поле in СПИСКОВІ:
        написала = any(not порожнє(u.get(поле)) and містить(u.get(поле), рядок['уривок']) for u in (оновлення or []))
    else:
        написала = any(not порожнє(u.get(поле)) for u in (оновлення or []))
    докази['модель_написала'] = написала
    паспорт_має = в_паспорті(р, запис['паспорт'], поле, рядок['уривок'])
    докази['паспорт'] = паспорт_має
    стилістка = у_стилістки(р, запис['розділи'], поле, рядок['уривок'])
    докази['стилістка'] = стилістка
    суд_без_входу = False
    if поле in р.суд:
        укр = р.ключ(поле)
        for л in запис['діагноз']:
            m = re.search(r'no_input=(.*)', л)
            for частина in (m.group(1).split(' | ') if m else []):
                п = re.fullmatch(r'\s*[^=]+=сценарій\.([^:]+): (\S+)\s*', частина)
                if not п or укр not in п.group(1).split('|'):
                    continue
                # причина `none` — значення поля немає; `none_or_cold_…` (K-OUT-33) — немає або холодно: немає лише
                # тоді, коли паспорт поля теж порожній (записи без паспорта — Gemini, `паспорта_нема` — цього не доводять:
                # «немає» не відрізнити від «холодно», тож тут не лічиться); інші причини (`sport_or_home`, `no_adjacent_step`,
                # `no_makeup_advice_applies`) — правило прочитало значення й не застосувалось, входу не бракує
                if п.group(2) == 'none' or (п.group(2).startswith('none_or_cold') and not паспорт_має and not запис.get('паспорта_нема')):
                    суд_без_входу = True
    докази['суд_без_входу'] = суд_без_входу
    if стилістка is None and запис.get('паспорта_нема') and написала is not False:
        return 'складання_нема', докази
    if стилістка and not суд_без_входу:
        return 'дійшло', докази
    if стилістка or паспорт_має:
        return 'читач', докази
    if написала is False:
        return 'модель', докази             # модель не записала — далі нічого не могло дійти, паспорт чи його брак не важить
    if паспорт_має is None:
        return 'писач_чи_читач', докази
    if написала is None:
        return 'модель_чи_писач', докази
    return 'писач', докази


def лічба(записи, таблиця, р):
    """Усі рядки лічби: по запису розмови, по репліці, по рядку таблиці читання (лише поля-читачі)."""
    рядки, без_читання = [], set()
    схема = set().union(*(з['схема'] for з in записи)) if записи else set()
    for з in записи:
        бачені = set()
        for репліка in з['репліки']:
            if репліка not in таблиця:
                без_читання.add(репліка)
                continue
            for т in таблиця[репліка]:
                if т['рівень'] == 'поза_обсягом':
                    continue
                ключ = (т['поле'], т['рівень'], т['уривок'] if т['поле'] in СПИСКОВІ else None)
                if ключ in бачені:
                    continue
                бачені.add(ключ)
                ст, док = стадія(р, з, репліка, т, схема)
                рядки.append({'запис': (з['прогін'], з['сцена'], з['прохід']), 'модель': з['модель'], 'репліка': репліка,
                              'поле': т['поле'], 'уривок': т['уривок'], 'рівень': т['рівень'], 'стадія': ст,
                              'докази': док})
    return рядки, без_читання


def згорнути(рядки):
    """Таблиця «поле · назвала · дійшло · губиться» по сценах (лише `пряме`) і окремо `виведене`.

    Одиниця — сцена прогону (її два проходи — один запис кожна) × поле; для полів-списків — ще й елемент (уривок).
    Сцена «дійшла», коли дійшло в усіх її проходах; інакше її місце втрати — стадія першого прохода, де не дійшло."""
    за_одиницями = collections.OrderedDict()
    for р in рядки:
        прогін, сцена, прохід = р['запис']
        елемент = р['уривок'] if р['поле'] in СПИСКОВІ else None
        к = (р['поле'], р['рівень'], прогін, сцена, елемент)
        за_одиницями.setdefault(к, []).append((прохід, р['стадія']))
    вих = {}
    for (поле, рівень, прогін, сцена, елемент), проходи in за_одиницями.items():
        з = вих.setdefault(поле, {'назвала': set(), 'дійшло': set(), 'втрата': collections.defaultdict(set),
                                  'виведене': set()})
        одиниця = (прогін, сцена, елемент)
        if рівень == 'виведене':
            з['виведене'].add(одиниця)
            continue
        з['назвала'].add(одиниця)
        невдалі = sorted(x for x in проходи if x[1] != 'дійшло')
        if not невдалі:
            з['дійшло'].add(одиниця)
        else:
            з['втрата'][невдалі[0][1]].add(одиниця)
    return вих


def місць(зведення):
    """Місце класу: сцена, у якій поле назване, а не дійшло (по полю й елементу)."""
    return sum(len(з['назвала']) - len(з['дійшло']) for з in зведення.values())


def таблиця_md(зведення, р, кількість_записів, з_складанням=False):
    додаток = ' складання не записано |' if з_складанням else ''
    рядки = ['| поле | читач | назвала в N сценах | дійшло в M | схема | модель | писач | читач | модель чи писач (відповіді моделі не записано) | писач чи читач (паспорта нема) |' + додаток + ' + виведене (не лічено) |',
             '|---|---|---:|---:|---:|---:|---:|---:|---:|---:|' + ('---:|' if з_складанням else '') + '---:|']
    for поле, з in sorted(зведення.items(), key=lambda x: -(len(x[1]['назвала']) - len(x[1]['дійшло']))):
        читач = ('суд' if поле in р.суд else '') + ('+' if поле in р.суд and р.ключі_стилістки(поле) else '') + \
            ('стилістка' if р.ключі_стилістки(поле) else '')
        в = з['втрата']
        рядки.append('| %s | %s | %d | %d | %d | %d | %d | %d | %d | %d |%s %d |' % (
            поле, читач, len(з['назвала']), len(з['дійшло']), len(в['схема']), len(в['модель']), len(в['писач']),
            len(в['читач']), len(в['модель_чи_писач']), len(в['писач_чи_читач']),
            (' %d |' % len(в['складання_нема'])) if з_складанням else '', len(з['виведене'])))
    return '\n'.join(рядки)


