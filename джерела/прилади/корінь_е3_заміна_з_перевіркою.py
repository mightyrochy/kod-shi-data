def пропозиція(текст, ремонт=False):
    """Відрізняє заміну речі/кольору від запиту входу, пояснення та носіння."""
    if not ремонт and re.fullmatch(r'[a-z][a-z0-9_]*', текст.strip()):
        return False, 'машинний код, не текст пропозиції'
    текст = re.sub(r'`[\w.]+`', '', текст).lower().replace('_', ' ')
    if not текст.strip():
        return False, 'порожнє значення або копія поля; нового рішення немає'
    # Відкидаємо лише заборонену дію, а не все речення: після неї буває альтернатива.
    # «взяти участь/до уваги» — не пропозиція взяти іншу річ.
    текст = re.sub(r'взяти\s+(?:участь|до уваги|на себе)', '', текст)
    чистий = ЗАБОРОНА.sub('', текст)
    if ремонт:
        if re.search(r'(?:взяти|узяти) тип|take from the day.s band.*types', чистий):
            return True, 'ремонт пропонує інший тип речі в смузі дня'
        if re.search(r'\b(?:replace|swap|remove|add)\b', чистий):
            return True, 'код/текст ремонту змінює склад або замінює річ'
        if re.search(r'\b(?:move|mute|match|keep|echo|tie|cover|take|shift|bring|put)\b', чистий) and ПРЕДМЕТ.search(чистий):
            if not re.search(r'gesture|wear asymmetrically|allowed state|raise collar|knot placement|her choice|from card|походження|запитати|виміряти', чистий):
                return True, 'ремонт змінює носія кольору, річ або склад образу'
    if not ремонт:
        # Згадка заміни, опис уже зробленого, вибір палітри/образу — не нова порада.
        чистий = re.sub(r'замість|\b(?:take|choose|replaced|removed|swapped|added|adding|replacement)\b', '', чистий)
        if re.search(r'choos\w* a replacement|item to replace|for replacing', текст):
            чистий += ' replace item'
        if re.search(r'choose exactly one different item', текст):
            чистий += ' replace item'
        if re.search(r'\b(?:do not|never|no suggestions|no .*for).*\b(?:swap|add|replace)', текст):
            return False, 'заборона пропонувати заміну або додаткову річ'
    if ремонт and re.search(r'\b(?:зняти|прибрати|додати|remove|add)\b', чистий):
        return True, 'ремонт додає або прибирає предмет, названий носієм/кодом заяви'
    if ДІЯ.search(чистий) and ПРЕДМЕТ.search(чистий):
        if not ВХІД.match(чистий) or re.search(r'або.*(?:інша|річ|пара|матова)|заміни|replace', чистий):
            return True, 'дія змінює склад образу або колір речі'
    # «Фото речі … або матова темна річ»: запит входу не знімає альтернативу після «або».
    після_або = re.search(r'\bабо\b(.*)', чистий)
    # Після запиту входу («фото…», «подати…») «або» ще не альтернатива: потрібна названа інша річ.
    вузький = re.compile(r'річ із|пара|матов|інш|светр|верх|накидк|жакет|шарф|макс[іи]|крою|кольо|колір')
    хвіст = (після_або.group(1) if після_або else '').replace('ця річ', '')
    альтернатива_після_або = bool(хвіст and (вузький if ВХІД.match(чистий) else ПРЕДМЕТ).search(хвіст))
    if ремонт and ПРЕДМЕТ.search(чистий) and (АЛЬТЕРНАТИВА.search(чистий) or альтернатива_після_або) \
            and (not ВХІД.match(чистий) or альтернатива_після_або):
        return True, 'ремонт називає альтернативну річ або колір без дієслова заміни'
    return False, 'запит даних, пояснення, носіння чи опис поля без пропозиції іншої речі/кольору'


def складові(текст):
    """Розбиває текст ремонту на складові з роздільником перед кожною: коди заяв, їхні параметри й «або» — межі."""
    текст = ПАРАМЕТРИ_ЗАЯВИ.sub(' ', КОД_ЗАЯВИ.sub(';', текст))
    вих, роздільник, позиція = [], '', 0
    for збіг in МЕЖА_СКЛАДОВОЇ.finditer(текст):
        вих.append((роздільник, текст[позиція:збіг.start()]))
        роздільник, позиція = збіг.group().strip().lower() or '.', збіг.end()
    вих.append((роздільник, текст[позиція:]))
    return [(р, re.sub(r'\s+', ' ', ф).strip()) for р, ф in вих if re.search(r'\w', ф)]


def клас_складової(складова, після_запиту=''):
    """Клас складової ремонту: запит даних, догляд, носіння — не заміни; решта — «заміна» чи «інше» (судить лишок)."""
    чистий = ЗАБОРОНА.sub('', складова.lower())
    сильна = bool(СИЛЬНА_ЗАМІНА.search(чистий))
    if сильна:
        return 'інше'
    if ЗАПИТ_ДАНИХ.match(чистий) or ВХІД.match(чистий):
        return 'запит'
    if після_запиту == 'пояснення':
        return 'запит'  # «міряти нема чого — вимір уже є. На цьому тілі … інші правила»: пояснення до запиту
    if після_запиту == 'або' and not re.search(
            r'річ із|пара|матов|інш|светр|верх|накидк|жакет|шарф|макс[іи]|крою|кольо|колір', чистий):
        return 'запит'  # «перевірити картку на слово про підошву або протектор»: «або» вхід не лишає альтернативою
    if ПОЯСНЕННЯ.search(чистий):
        return 'пояснення'
    if ДОГЛЯД.search(чистий):
        return 'догляд'
    if НОСІННЯ.search(чистий):
        return 'носіння'
    return 'інше'


def складові_заміни(текст):
    """Складові-заміни ремонту (рішення 08.11): `(так, причина, [складові])`, відкинуті — носіння, догляд, запит даних.

    Спершу відкидаються складові, що самі по собі не заміна; решту судить `пропозиція` разом (дія в одній складовій,
    предмет у сусідній), далі — кожна окремо (англійська іменна альтернатива, «instead of»)."""
    частини, лишок, попередній, злите = складові(текст), [], '', ''
    if not частини:
        # лише код заяви без людського тексту: складових нема, судить сам код (як до рішення 08.11)
        так, причина = пропозиція(текст, ремонт=True)
        return (True, причина, [текст.strip()]) if так else (False, причина, [])
    for роздільник, складова in частини:
        після = ('' if попередній != 'запит' else 'або' if роздільник in {'або', 'or'}
                 else 'пояснення' if роздільник in {'—', '–', '.', '!', '?', ','} else '')
        клас = клас_складової(складова, після)
        попередній = клас
        if клас == 'інше':
            злите += (' або ' if роздільник in {'або', 'or'} and лишок else '; ' if лишок else '') + складова
            лишок.append(складова)
    так, причина = пропозиція(злите, ремонт=True) if лишок else (False, '')
    знайдені = [с for с in лишок if ' ' in с and пропозиція(с, ремонт=True)[0]]
    if так and not знайдені:
        знайдені = [злите]
    if not так:
        for складова in лишок:
            ч = ЗАБОРОНА.sub('', складова.lower())
            англ = (АНГЛ_АЛЬТЕРНАТИВА.match(ч) and АНГЛ_ПРЕДМЕТ.search(ч) and not АНГЛ_ОПИС.search(ч)
                    and re.search(r'[a-z]{3}', ч) and not re.search(r'[а-яіїєґ]', ч))
            інстед = re.search(r'\binstead of\b', ч) and (ПРЕДМЕТ.search(ч) or АНГЛ_ПРЕДМЕТ.search(ч))
            if англ or інстед:
                так, причина = True, 'ремонт називає альтернативу англійською: ' + ('іменна' if англ else 'use … instead of')
                знайдені.append(складова)
    if так:
        return True, причина, знайдені
    відкинуті = [ф for р, ф in частини if клас_складової(ф) != 'інше']
    return False, ('запит даних, пояснення, носіння чи догляд без пропозиції іншої речі/кольору'
                   if відкинуті or not лишок else
                   'пояснення чи опис поля без пропозиції іншої речі/кольору'), []


def поля(вузол, вкладені=None):
    """Повертає поля літерала словника або виклику з іменованими аргументами.

    `вкладені` збирає словники й виклики, чиї поля влито сюди (`dict(зн(…), …)`, `**зн(…)`): їхня група
    ремонту — та сама, що в зовнішнього вузла, і окремим виробником її не лічать (13857)."""
    вих = {}
    if isinstance(вузол, ast.IfExp):
        return {}  # Гілки обходяться окремо, не затіняючи одна одну.

    def влити(в):
        if вкладені is not None:
            вкладені.append(в)
        вих.update(поля(в, вкладені))

    if isinstance(вузол, ast.Dict):
        for к, з in zip(вузол.keys, вузол.values):
            if к is None:
                влити(з)
            elif isinstance(к, ast.Constant) and isinstance(к.value, str):
                вих[к.value] = з
    if isinstance(вузол, ast.Call):
        if isinstance(вузол.func, ast.Name) and вузол.func.id == 'dict':
            for а in вузол.args:
                влити(а)
        for к in вузол.keywords:
            if к.arg:
                вих[к.arg] = к.value
            else:
                влити(к.value)
    return вих


