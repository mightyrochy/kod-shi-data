# -*- coding: utf-8 -*-
"""Зворотний бік частини (ґ) розвідки «Приховані»: записи журналу власника без сліду в правилах роботи.

Ядро («Пам'ять»): слово власника записують у `аудит/РІШЕННЯ_ВЛАСНИКА.md` тим самим PR, що й правила, які воно змінює;
`аудит/МЕНЕДЖЕР.md` («Правила»): умова слова двічі лишалась лише в журналі. Прилад перелічує записи журналу зі штампом
«- **ДД.ММ.2026 …**» від дати `--від` і позначає ті, де після «→» нема жодного файлу правил (ядро, адаптери, файли
ролей і додатки, план, картина, `аудит/ПРОДУКТ.md`) або нема «→» взагалі. Не судить: питання власника, слово про продукт поза
правилами чи відповідь у чаті теж дають «без файлу» — кожен такий запис потребує вердикту сесії.

Запуск з кореня репозиторію:
  python3 джерела/прилади/приховані_g_зворот.py [--від 22.10]          лічба
  python3 джерела/прилади/приховані_g_зворот.py --усі [--від 22.10]    рядок ⇥ стан ⇥ початок запису
  python3 джерела/прилади/приховані_g_зворот.py --перелік аудит/корені/Приховані-перелік-ґ.md [--від 22.10]
      покриття: запис покритий, коли «ґз:<рядок журналу>» стоїть першою клітинкою рядка таблиці переліку.
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from приховані_g_межі import покриті  # noqa: E402

КОРІНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ЖУРНАЛ = "аудит/РІШЕННЯ_ВЛАСНИКА.md"
_ПРАВИЛА = re.compile(r"AGENTS|CLAUDE|GEMINI|CHATGPT|НОУТБУК|КЕРУВАННЯ|НАЛАШТУВАННЯ|ЧЕРГА|МЕНЕДЖЕР|ДИСПЕТЧЕР|"
                      r"ВИКОНАВЕЦЬ|ПЕРЕВІРКА|МОДЕЛІ|КОД\.md|живі_порядок|ПРОДУКТ|СТАНДАРТ_КОДУ|ПЛАН|КАРТИН|ядр")


def записи(від):
    рядки = open(os.path.join(КОРІНЬ, ЖУРНАЛ), encoding="utf-8").read().split("\n")
    усі, поточний = [], None
    for н, р in enumerate(рядки, 1):
        м = re.match(r"- \*\*(\d{1,2})\.(\d{2})", р)
        if м:
            поточний = [н, (int(м.group(2)), int(м.group(1))), р]
            усі.append(поточний)
        elif р.startswith(("- ", "## ")) or not р.strip():
            поточний = None
        elif поточний:
            поточний[2] += " " + р.strip()
    д, м = (int(x) for x in від.split("."))
    вихід = []
    for н, дата, текст in усі:
        if дата < (м, д):
            continue
        if "→" not in текст:
            стан = "без →"
        elif not _ПРАВИЛА.search(текст.split("→", 1)[1]):
            стан = "→ без файлу правил"
        else:
            стан = "у правилах"
        вихід.append((н, стан, текст[:140]))
    return вихід


def main():
    п = argparse.ArgumentParser()
    п.add_argument("--від", default="22.10")
    п.add_argument("--усі", action="store_true")
    п.add_argument("--перелік")
    а = п.parse_args()
    вс = записи(а.від)
    if а.усі:
        for н, с, т in вс:
            print("%d\t%s\t%s" % (н, с, т))
        return
    лічба = {}
    for _, с, _ in вс:
        лічба[с] = лічба.get(с, 0) + 1
    print("записів від %s: %d — %s" % (а.від, len(вс), ", ".join("%s %d" % кв for кв in sorted(лічба.items()))))
    if а.перелік:
        покрито = покриті(а.перелік, "ґз:")
        ід = {"ґз:%d" % н for н, _, _ in вс}
        є = len(ід & покрито)
        print("з вердиктом %d з %d (%.0f %%)" % (є, len(ід), 100.0 * є / max(1, len(ід))))
        зайві = sorted(покрито - ід)
        if зайві:
            print("ід переліку без запису (зсув рядків?): %d — %s" % (len(зайві), ", ".join(зайві[:8])))


if __name__ == "__main__":
    main()
