"""Відтворити записані VIDPOVIDI без моделі та мережі; джерела записані в корпусі."""
import argparse
import contextlib
import io
import inspect
import json
import re
import sys
import zipfile
from pathlib import Path


def виміряти(корпус, код=None):
    """Прогнати ті самі записи через задану версію ядра й повернути лічбу та докази."""
    sys.path.insert(0, str(код or Path(__file__).resolve().parents[1]))
    with contextlib.redirect_stdout(io.StringIO()):
        import мовний_шар as м
        import паспорт_поля as пп
    записи = json.loads(Path(корпус).read_text(encoding='utf8'))
    л = dict(ходів=0, поточних=0, her_без_уривка=0, година_без_числа=0,
             названих_годин=0, втрачено_годин=0, нагода_стерта=0,
             реплік=0, службові_recorded=0, числа_recorded=0,
             плиток=0, типове_chosen=0, показаних=0, без_підтвердження=0,
             J_поганих=0, J_відмов=0, J_добрих=0, J_хибних=0, обрубків_до_показу=0,
             без_дослівного_підтвердження=0,
             цитат_перед_плитками=0, стерта_цитата=0, змінена_пора=0, масив_нагод_втрачено=0,
             годин_словами=0, година_словами_не_тлумачення=0)
    стани, запрошення, частини_ходів, докази = {}, {}, {}, []

    def сцена(з):
        """Стабільний ключ сцени із git-шляху, незалежно від її виду запису."""
        return з['джерело'].split(':', 1)[1].split('/VIDPOVIDI/')[0].removesuffix('/лог.txt')

    def н(т):
        """Нормалізувати регістр, пробіли та апостроф для дослівного зіставлення."""
        return ' '.join(str(т).lower().replace('’', "'").replace('ʼ', "'").split())

    def опора(т, п):
        """Старий аналітичний J розбору: цитата й відсутність чужих цифр."""
        уривки = [ф['уривок'] for ф in п.get('картка_запиту', {}).values()
                  if пп.на_її_словах(ф) and ф.get('уривок')]
        return bool(any(н(ц) in н(т) for ц in уривки)) and all(
            any(ц in у for у in уривки) for ц in re.findall(r'\d+', т))

    for з in записи:
        if з['вид'] != 'розмова':
            continue
        запит, відповідь = з['запит'], з['відповідь']
        прийнято = м.прийняти_розмову(json.dumps(відповідь, ensure_ascii=False))
        вн = прийнято.get('внутрішня') or {}
        with contextlib.redirect_stdout(io.StringIO()):
            р = м.паспорт_з_шару(вн, {}, слова_ходу=[запит.get('her_new_message', '')],
                                 частини=прийнято.get('частини'))
        п = р['паспорт']
        стани[сцена(з)] = р
        частини_ходів[сцена(з)] = прийнято.get('частини') or {}
        запрошення[сцена(з)] = str((відповідь.get('invite') or '')).strip()
        картка = п.get('картка_запиту', {})
        л['ходів'] += 1
        л['поточних'] += int('ПІСЛЯ_main' in з['джерело'] or '/живі_3.2е/ПІСЛЯ/' in з['джерело'])
        л['her_без_уривка'] += sum(ф.get('джерело') == 'her' and not ф.get('уривок') for ф in картка.values())
        ф = картка.get('година', {})
        # її година — лише цифрами в її уривку (`паспорт_поля.дослівно`, рішення менеджера 31.10)
        л['година_без_числа'] += int(ф.get('джерело') == 'her' and not пп.дослівно(ф.get('значення'), ф.get('уривок')))
        година = (відповідь.get('update') or {}).get('hour') or {}
        if isinstance(година, dict) and година.get('named') == 'clock_time' and not пп.дослівно(година.get('value'), година.get('quote')):
            # година без її цифр — тлумачення моделі з її уривком, не її факт і не загублений уривок
            л['годин_словами'] += 1
            л['година_словами_не_тлумачення'] += int(ф.get('джерело') != пп.ТЛУМАЧЕННЯ or not ф.get('уривок'))
        if isinstance(година, dict) and година.get('named') == 'clock_time' and пп.дослівно(година.get('value'), година.get('quote')):
            л['названих_годин'] += 1
            л['втрачено_годин'] += int(п.get('година') != година['value'])
        л['нагода_стерта'] += int(bool(вн.get('occasion')) and not п.get('нагода'))
        нагода = (відповідь.get('update') or {}).get('occasion')
        л['масив_нагод_втрачено'] += int(isinstance(нагода, dict) and isinstance(нагода.get('value'), list)
                                      and not п.get('нагода'))
        л['обрубків_до_показу'] += int(bool(р.get('текст')) and any(
            в.get('чому') == 'extra_sentence' for в in р.get('відкинуто') or []))
        докази.append(dict(джерело=з['джерело'], картка=картка, записано=р.get('записано'), текст=р.get('текст')))

    for з in записи:
        if з['вид'] == 'розмова':
            continue
        р = стани.get(сцена(з), {})
        п = р.get('паспорт', {})
        if з['вид'] == 'репліка':
            л['реплік'] += 1
            записано = м.записано_для_репліки(з['запит'].get('recorded', {}), п) or {}
            л['службові_recorded'] += int(bool(set(записано) & {'occasion_part', 'formality_branch', 'formality_reason'}))
            л['числа_recorded'] += int(any(isinstance(в, (int, float)) for в in записано.values()))
            л['J_поганих'] += 1
            суд = getattr(м, 'суд_підтвердження', None)
            л['J_відмов'] += int(not суд(з['відповідь'].get('text', ''), записано)[0] if суд else not опора(з['відповідь'].get('text', ''), п))
        elif з['вид'] == 'плитки':
            л['плиток'] += 1
            обрано = з['запит'].get('chosen', {})
            с = {ім: м._ВМ.ключ(о['поле'], обрано[о['поле']]) if о['поле'] in м._ВМ.ТАБЛИЦЯ else обрано[о['поле']]
                 for ім, о in м._ВМ.ПОЛЯ_ПАСПОРТА.items() if о.get('поле') in обрано and not ім.startswith('@')}
            с['картка_запиту'] = п.get('картка_запиту', {})
            обрано = м.плитки_кодами(с)
            л['типове_chosen'] += int(обрано.get('hour') == 11 or обрано.get('temperature_c') == 18)
            прийнято = м.прийняти_хід_плиток(json.dumps(з['відповідь'], ensure_ascii=False))
            арг = dict(паспорт_досі=п, слова_ходу=[])
            if 'лише_плитки' in inspect.signature(м.паспорт_з_шару).parameters:
                арг['лише_плитки'] = True
            після = м.паспорт_з_шару(прийнято.get('внутрішня') or {}, с, **арг)['паспорт']
            ц = (п.get('цитати_полів') or {}).get('пора')
            if ц:
                л['цитат_перед_плитками'] += 1
                л['стерта_цитата'] += int((після.get('цитати_полів') or {}).get('пора') != ц)
                л['змінена_пора'] += int(після.get('пора') != п.get('пора'))
        elif з['вид'] == 'показ':
            т = з['відповідь']['text']
            л['показаних'] += 1
            if з.get('очікування_J') == 'good':
                л['J_добрих'] += 1
                суд = getattr(м, 'суд_підтвердження', None)
                запис = м.записано_для_репліки(р.get('записано') or {}, п) or {}
                власний = т.removesuffix(запрошення.get(сцена(з), '')).strip() if запрошення.get(сцена(з)) else т
                л['J_хибних'] += int(bool(суд and not суд(власний, запис)[0]))  # запрошення судить суд_частин, не J
            факти = bool(п.get('цитати_полів'))
            if hasattr(м, 'суд_підтвердження'):
                л['без_дослівного_підтвердження'] += int(bool(р.get('текст')) and факти and not опора(р['текст'], п))
                # Паспорт повертає показ із запрошенням; підтвердження перевіряємо
                # окремо, на тих самих частинах записаного ходу, що й живий суд.
                запис = м.записано_для_репліки(р.get('записано') or {}, п) or {}
                арг = {'картка': запис} if 'картка' in inspect.signature(м._текст_до_показу).parameters else {}
                власний, _, _ = м._текст_до_показу(частини_ходів[сцена(з)], запис, **арг)
                л['без_підтвердження'] += int(bool(р.get('текст')) and факти and not м.суд_підтвердження(власний, запис)[0])
            else:
                л['без_підтвердження'] += int(факти and not опора(т, п))
    return dict(лічба=л, ходи=докази)


def main():
    """CLI для незалежного повтору ДО й ПІСЛЯ на одному корпусі."""
    а = argparse.ArgumentParser(description=__doc__)
    а.add_argument('корпус', type=Path)
    а.add_argument('--код', type=Path)
    а.add_argument('--запис', type=Path)
    а.add_argument('--архів', type=Path, help='архів цих джерел і проб для локального Pyodide')
    п = а.parse_args()
    if п.архів:
        джерела = Path(__file__).resolve().parents[1]
        додаткові = ('проби/картка_події.py', 'проби/картка_replay.py',
                     'прилади/replay_картки.py', 'проби/дані/картка_запиту.json')
        with zipfile.ZipFile(п.архів, 'w', zipfile.ZIP_DEFLATED) as архів:
            for файл in list(джерела.glob('*.py')) + [джерела / ім for ім in додаткові]:
                архів.write(файл, файл.relative_to(джерела))
    р = виміряти(п.корпус, п.код)
    if п.запис:
        п.запис.write_text(json.dumps(р, ensure_ascii=False, indent=1), encoding='utf8')
    print(json.dumps(р['лічба'], ensure_ascii=False))


if __name__ == '__main__':
    main()
