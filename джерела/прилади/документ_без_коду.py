def _останні(запуски):
    """Останній запуск на кожен робочий процес (за id; скасовані старші конкурентністю не рахуються)."""
    за_шляхом = {}
    for з in запуски:
        шл = (з.get("path") or "").split("@")[0]
        if шл not in за_шляхом or з["id"] > за_шляхом[шл]["id"]:
            за_шляхом[шл] = з
    return за_шляхом


def _запуск_check_run(к):
    """id запуску Actions, якому належить check run (з `details_url` …/actions/runs/<id>/job/…), чи None."""
    шматки = (к.get("details_url") or "").split("/actions/runs/", 1)
    if len(шматки) == 2 and шматки[1].split("/", 1)[0].isdigit():
        return int(шматки[1].split("/", 1)[0])
    return None


def перевірки_голови(голова, запуски, check_runs, статуси, свій_запуск=""):
    """(усе зелене?, причина) для голови PR; check runs власного запуску кроку (`свій_запуск`) не рахуються.

    Кожен запуск процесу — свій check suite, а `filter=latest` лишає останні check runs кожного suite, тож check runs
    витісненого запуску (новіший запуск того самого процесу на тій самій голові) лишаються в списку: їх не рахуємо.
    Check run, чий запуск не серед запусків голови від PR (чи без запуску), рахується, як і раніше, крім job-ів процесу
    самозлиття (`JOB_САМОЗЛИТТЯ`): їхні check runs, зокрема скасований чергою «злиття», не рахуються."""
    запуски = [з for з in запуски if з.get("head_sha") == голова and з.get("event") == "pull_request"]
    запуски_pr = {з["id"] for з in запуски}
    за_шляхом = _останні(запуски)
    витіснені = {з["id"] for з in запуски} - {з["id"] for з in за_шляхом.values()}
    for шл in ОБОВЯЗКОВІ:
        if шл not in за_шляхом:
            return False, f"нема запуску {шл} на голові"
    for шл, з in sorted(за_шляхом.items()):
        if з.get("status") != "completed":
            return False, f"запуск {шл} ще йде ({з.get('status')})"
        if з.get("conclusion") not in ДОБРІ:
            return False, f"запуск {шл}: {з.get('conclusion')}"
    for к in check_runs:
        if свій_запуск and f"/actions/runs/{свій_запуск}/" in (к.get("details_url") or ""):
            continue
        if _запуск_check_run(к) in витіснені:
            continue
        # job процесу самозлиття (запуск не від `pull_request`: `workflow_run`/`pull_request_target`) — не CI голови
        if (к.get("name") or "").startswith(JOB_САМОЗЛИТТЯ) and _запуск_check_run(к) not in запуски_pr:
            continue
        if к.get("status") != "completed":
            return False, f"перевірка «{к.get('name')}» ще йде"
        if к.get("conclusion") not in ДОБРІ:
            return False, f"перевірка «{к.get('name')}»: {к.get('conclusion')}"
    останні_статуси = {}
    for с in статуси:  # API віддає новіші першими
        останні_статуси.setdefault(с.get("context"), с)
    for контекст, с in sorted(останні_статуси.items()):
        if с.get("state") != "success":
            return False, f"статус «{контекст}»: {с.get('state')}"
    return True, "перевірки голови зелені"


def _умови_pr(pr):
    """Причина відмови за станом PR (без файлів і перевірок) чи None; спільне для документа й мітки."""
    if pr.get("state") != "open":
        return "PR не відкритий"
    if pr.get("draft"):
        return "чернетка"
    if (pr.get("user") or {}).get("login") != АВТОР:
        return f"автор {(pr.get('user') or {}).get('login')}, не {АВТОР}"
    голова, база = pr.get("head") or {}, pr.get("base") or {}
    if ((голова.get("repo") or {}).get("full_name") != РЕПОЗИТОРІЙ
            or (база.get("repo") or {}).get("full_name") != РЕПОЗИТОРІЙ):
        return "голова чи база не з цього репозиторію (форк)"
    if база.get("ref") != БАЗА:
        return f"база {база.get('ref')}, не {БАЗА}"
    if (голова.get("ref") or "").casefold().startswith(ГІЛКИ_НЕ_САМІ):
        return f"гілка голови {голова.get('ref')}: PR агента Copilot зливає диспетчер, не самозлиття"
    return None


def _повний_список_файлів(pr, файли):
    return len(файли) == pr.get("changed_files") and len(файли) < МАКС_ФАЙЛІВ


def рішення_pr(pr, файли, запуски, check_runs, статуси, свій_запуск=""):
    """(злити?, причина) для одного PR за записаними відповідями API."""
    відмова = _умови_pr(pr)
    if відмова:
        return False, відмова
    голова = pr.get("head") or {}
    if not _повний_список_файлів(pr, файли):
        return False, f"список файлів неповний ({len(файли)} з {pr.get('changed_files')})"
    так, перший, чому = вердикт(з_api(файли))
    if not так:
        return False, f"прилад: ні — {перший}: {чому}"
    return перевірки_голови(голова.get("sha"), запуски, check_runs, статуси, свій_запуск)


def _файли_коду(pr, файли):
    """Причина відмови самозлиттю коду; перевіряємо обидва імені, які повертає GitHub для перейменування."""
    if not _повний_список_файлів(pr, файли):
        return f"список файлів неповний ({len(файли)} з {pr.get('changed_files')})"
    if not файли:
        return "порожній список змін"
    for _, новий, старий in з_api(файли):
        for п in (новий, старий):
            if п and (п.startswith(ЗАКРИТІ_ТЕКИ) or п in ЗАКРИТІ_ФАЙЛИ or п.rsplit("/", 1)[-1] in ПРАВИЛА_БУДЬ_ДЕ
                      or fnmatch.fnmatchcase(п, "джерела/прилади/документ_без_коду_*.json")):
                ім_я = п.replace("\n", r"\n").replace("\r", r"\r")
                return f"закрите місце: {ім_я}"
    return None


def _час(текст):
    return datetime.datetime.strptime(текст, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=datetime.timezone.utc)


def _зараз():
    return datetime.datetime.now(datetime.timezone.utc)


def _початок_першого_ci(api, голова, запуски):
    """Перший старт CI на цьому SHA, включно з першою спробою повторно запущених workflow."""
    початки = []
    for запуск in запуски:
        if запуск.get("event") != "pull_request" or запуск.get("head_sha") != голова:
            continue
        if (запуск.get("run_attempt") or 1) > 1:
            try:
                код, запуск, _ = api.запит("GET", f"/repos/{api.р}/actions/runs/{запуск['id']}/attempts/1")
            except (OSError, ValueError):
                continue
            if код != 200 or not запуск or запуск.get("head_sha") != голова:
                continue
        початок = запуск.get("run_started_at")
        if початок:
            початки.append(початок)
    return min(початки, default=None)


def _мітка_стан(pr, події, статуси, зараз=None):
    """(діє?, причина, стара?): мітка «злити» стоїть на PR, поставлена `mightyrochy` на САМІЙ поточній голові.

    Мітку прив'язано до SHA голови, а не до дат (коміт, пуш і мітка — це різні годинники; дошка 17101, доробка #4718):
    у момент події `labeled` job `мітка` (`samozlyttia.yml`) ставить на SHA голови зі сніпшота події статус
    `КОНТЕКСТ_МІТКИ` — лише коли мітку поставив `mightyrochy`. Мітка діє, доки на ПОТОЧНІЙ голові PR є такий статус,
    створений `github-actions[bot]` не раніше за останню подію `labeled`: новий коміт (будь-який пуш, дата коміту
    не важить) — іншого SHA статуса нема; запізнілі запуски CI мітку не гасять. `head_ref_force_pushed` після мітки —
    мітка стара навіть на SHA, що вже мав статус (повернення голови на старий коміт). Нема статуса на голові, коли
    від мітки минуло понад `ПІЛЬГА_СТАТУСА` (job мітки не встиг чи голова змінилась), — мітка стара. `події` — GET
    /issues/{n}/events, `статуси` — GET /commits/{голова}/statuses (новіші першими)."""
    if МІТКА not in {(м or {}).get("name") for м in pr.get("labels") or []}:
        return False, f"мітки «{МІТКА}» на PR нема", False
    мітки = [п for п in події if п.get("event") == "labeled" and (п.get("label") or {}).get("name") == МІТКА]
    if not мітки:
        return False, f"мітка «{МІТКА}» є, а події її постановки нема", False
    остання = max(мітки, key=lambda п: (п.get("created_at") or "", п.get("id") or 0))
    хто = (остання.get("actor") or {}).get("login")
    if хто != АВТОР:
        return False, f"мітку поставив {хто}, не {АВТОР}", False
    час_мітки = остання.get("created_at")
    if not час_мітки:
        return False, "нема часу мітки — мітка не діє", False
    пізніше = [п for п in події if п.get("event") == "head_ref_force_pushed" and (п.get("created_at") or "") > час_мітки]
    if пізніше:
        return False, f"після мітки був force-push ({пізніше[-1].get('created_at')}): мітку знято", True
    за_контекстом = [с for с in статуси if с.get("context") == КОНТЕКСТ_МІТКИ]
    статус = за_контекстом[0] if за_контекстом else None  # новіші першими
    if (статус and статус.get("state") == "success" and (статус.get("creator") or {}).get("login") == БОТ
            and (статус.get("created_at") or "") >= час_мітки):
        return True, f"мітка від {АВТОР} {час_мітки} зафіксована на цій голові ({статус['created_at']})", False
    зараз = зараз or _зараз()
    if зараз - _час(час_мітки) > ПІЛЬГА_СТАТУСА:
        return False, (f"мітка {час_мітки} не зафіксована на поточній голові — голова з'явилась знову (новий коміт, "
                       "rebase) чи job фіксації не відпрацював; постав мітку ще раз"), True
    return False, "мітка щойно поставлена — чекаю фіксації на голові (job `мітка`)", False


def мітка_діє(pr, події, статуси, зараз=None):
    """(діє?, причина) — див. `_мітка_стан`."""
    діє, чому, _ = _мітка_стан(pr, події, статуси, зараз)
    return діє, чому


def мітка_стара(pr, події, статуси, зараз=None):
    """Мітка «злити» від `mightyrochy` стоїть, але голова з'явилась знову після неї (новий коміт, rebase,
    force-push): CI її знімає й лишає коментар у PR (`прибрати_старі`)."""
    return _мітка_стан(pr, події, статуси, зараз)[2]


def рішення_мітка(pr, події, запуски, check_runs, статуси, свій_запуск="", зараз=None):
    """(злити?, причина) для PR, що не документ: мітка «злити» на поточній голові й зелені перевірки голови."""
    відмова = _умови_pr(pr)
    if відмова:
        return False, відмова
    діє, чому = мітка_діє(pr, події, статуси, зараз)
    if not діє:
        return False, чому
    зелене, чому_ci = перевірки_голови((pr.get("head") or {}).get("sha"), запуски, check_runs, статуси, свій_запуск)
    return (зелене, f"{чому}; {чому_ci}")


class API:
    def __init__(self, токен, репозиторій, адреса="https://api.github.com"):
        self.токен, self.р, self.адреса = токен, репозиторій, адреса.rstrip("/")

    def запит(self, метод, шлях, тіло=None):
        дані = None if тіло is None else json.dumps(тіло).encode()
        з = urllib.request.Request(self.адреса + шлях, data=дані, method=метод, headers={
            "Authorization": f"Bearer {self.токен}", "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28", "Content-Type": "application/json", "User-Agent": "samozlyttia"})
        try:
            with urllib.request.urlopen(з, timeout=60) as в:
                return в.status, json.loads(в.read() or b"null"), в.headers.get("Link", "")
        except urllib.error.HTTPError as п:
            try:
                return п.code, json.loads(п.read() or b"null"), ""
            except ValueError:
                return п.code, None, ""

    def усі(self, шлях, ключ=None, межа=30):
        """GET зі сторінками (per_page=100) до `межа` сторінок."""
        роздільник = "&" if "?" in шлях else "?"
        усе, сторінка = [], 1
        while сторінка <= межа:
            код, дані, link = self.запит("GET", f"{шлях}{роздільник}per_page=100&page={сторінка}")
            if код != 200:
                raise RuntimeError(f"GET {шлях}: {код} {дані}")
            частина = дані[ключ] if ключ else дані
            усе.extend(частина)
            if 'rel="next"' not in link:
                break
            сторінка += 1
        return усе


ЗАПИТ_ТРЕДІВ = """
query ($owner: String!, $repo: String!, $number: Int!, $cursor: String) {
  repository(owner: $owner, name: $repo) {
    pullRequest(number: $number) {
      headRefOid
      readyForReview: timelineItems(last: 1, itemTypes: [READY_FOR_REVIEW_EVENT]) {
        nodes { ... on ReadyForReviewEvent { createdAt } }
      }
      reviewThreads(first: 100, after: $cursor) {
        pageInfo { hasNextPage endCursor }
        nodes {
          isResolved
          firstComment: comments(first: 1) { nodes { author { __typename login } url } }
          lastComment: comments(last: 1) { nodes { author { __typename login } } }
        }
      }
    }
  }
}
"""


def _рецензії_коду(api, н, голова, початок_ci=None):
    """REST підтверджує рецензію, GraphQL дає останній вихід із чернетки й стан кожного треда."""
    try:
        рецензент = None
        for р in api.усі(f"/repos/{api.р}/pulls/{н}/reviews"):
            if р.get("commit_id") == голова and р.get("state") in {"APPROVED", "COMMENTED", "CHANGES_REQUESTED"}:
                рецензент = БОТИ_РЕЦЕНЗІЇ_REST.get((р.get("user") or {}).get("login"))
                if рецензент:
                    break
    except (RuntimeError, OSError, ValueError, TypeError, AttributeError):
        return False, "не вдалося прочитати рецензії"
    if not рецензент and not початок_ci:
        return False, "рецензії на голові нема, бракує часу першого CI на голові"

    власник, репозиторій = api.р.split("/", 1)
    змінні = {"owner": власник, "repo": репозиторій, "number": н, "cursor": None}
    try:
        for _ in range(30):
            код, дані, _ = api.запит("POST", "/graphql", {"query": ЗАПИТ_ТРЕДІВ, "variables": змінні})
            if код != 200 or not дані or дані.get("errors"):
                return False, f"не вдалося прочитати треди рецензії (GraphQL, HTTP {код})"
            pr = дані["data"]["repository"]["pullRequest"]
            if pr["headRefOid"] != голова:
                return False, "голова змінилась під час читання тредів"
            if рецензент:
                причина = f"рецензія {рецензент} на голові"
            else:
                події = pr["readyForReview"]["nodes"]
                початок_очікування = max([_час(початок_ci)] + [_час(п["createdAt"]) for п in події])
                хвилин = max(0, (_зараз() - початок_очікування) // datetime.timedelta(minutes=1))
                причина = f"рецензії на голові нема, голові {хвилин} хв"
                if хвилин < ХВИЛИН_ДЛЯ_РЕЦЕНЗІЇ:
                    return False, причина
            треди = pr["reviewThreads"]
            for тред in треди["nodes"]:
                перший, = тред["firstComment"]["nodes"]
                бот = перший["author"] or {}
                # REST додає [bot], GraphQL віддає логін без суфікса й окремий тип Bot.
                назва = БОТИ_РЕЦЕНЗІЇ.get(бот.get("login")) if бот.get("__typename") == "Bot" else None
                if назва is None or тред["isResolved"] is True:
                    continue
                останній, = тред["lastComment"]["nodes"]
                автор = останній["author"] or {}
                if автор.get("login") != АВТОР or автор.get("__typename") != "User":
                    return False, f"тред {назва} без відповіді: {перший['url']}"
            сторінка = треди["pageInfo"]
            if сторінка["hasNextPage"] is False:
                return True, f"{причина}, треди ботів розібрані"
            курсор = сторінка["endCursor"]
            if not курсор or курсор == змінні["cursor"]:
                break
            змінні["cursor"] = курсор
    except (KeyError, TypeError, OSError, ValueError, AttributeError):
        return False, "не вдалося прочитати треди рецензії (неповна відповідь GraphQL)"
    return False, "не вдалося прочитати всі сторінки тредів рецензії"


def обійти(api, свій_запуск="", старі=None, початки_ci=None):
    """Відкриті PR → [(номер, голова, злити?, причина, спосіб)]; спосіб — «документ», «мітка» чи «код».

    `старі` поповнюється PR із застарілою міткою, `початки_ci` — часом першого CI на головах кандидатів коду."""
    р = f"/repos/{api.р}"
    підсумок = []
    for коротко in api.усі(f"{р}/pulls?state=open&base={БАЗА}"):
        н = коротко["number"]
        г = коротко.get("head") or {}
        if коротко.get("draft"):
            підсумок.append((н, г.get("sha", ""), False, "чернетка", "код"))
            continue
        if (коротко.get("user") or {}).get("login") != АВТОР or (г.get("repo") or {}).get("full_name") != РЕПОЗИТОРІЙ:
            підсумок.append((н, г.get("sha", ""), False, "чужий автор або форк", "код"))
            continue
        код, pr, _ = api.запит("GET", f"{р}/pulls/{н}")
        if код != 200:
            підсумок.append((н, "", False, f"GET PR: {код}", "код"))
            continue
        голова = pr["head"]["sha"]
        відмова = _умови_pr(pr)
        if відмова:
            підсумок.append((н, голова, False, відмова, "код"))
            continue
        файли = api.усі(f"{р}/pulls/{н}/files")
        з_міткою = МІТКА in {(м or {}).get("name") for м in pr.get("labels") or []}
        документ = вердикт(з_api(файли))[0] and len(файли) == pr.get("changed_files")
        закрите = None if документ else _файли_коду(pr, файли)
        if закрите and not з_міткою:
            підсумок.append((н, голова, False, закрите, "код"))
            continue
        запуски = api.усі(f"{р}/actions/runs?head_sha={голова}&event=pull_request", "workflow_runs", 3)
        check_runs = api.усі(f"{р}/commits/{голова}/check-runs?filter=latest", "check_runs", 5)
        статуси = api.усі(f"{р}/commits/{голова}/statuses", None, 3)
        так, чому, спосіб = False, "", "код"
        if документ:
            так, чому = рішення_pr(pr, файли, запуски, check_runs, статуси, свій_запуск)
            спосіб = "документ"
        if not так and з_міткою:
            події = api.усі(f"{р}/issues/{н}/events", None, 3)
            так, чому = рішення_мітка(pr, події, запуски, check_runs, статуси, свій_запуск)
            спосіб = "мітка"
            if старі is not None and мітка_стара(pr, події, статуси):
                старі.append({"номер": н, "голова": голова})
        if not так and not документ:
            причина_мітки = f" · {чому}" if з_міткою else ""
            так, чому = (False, закрите) if закрите else перевірки_голови(голова, запуски, check_runs, статуси, свій_запуск)
            if так:
                початок_ci = _початок_першого_ci(api, голова, запуски)
                так, рецензії = _рецензії_коду(api, н, голова, початок_ci)
                чому = f"{чому}; {рецензії}" if так else рецензії
                if так and початок_ci and початки_ci is not None:
                    початки_ci[н] = початок_ci
            if not так:
                чому += причина_мітки
            спосіб = "код"
        підсумок.append((н, голова, так, чому, спосіб))
    return підсумок


def зняти_мітку(api, н, пояснення):
    """Знімає мітку «злити» з PR і лишає в ньому коментар з причиною; (знято?, рядок підсумку). Нема мітки — нічого."""
    р = f"/repos/{api.р}"
    код, _, _ = api.запит("DELETE", f"{р}/issues/{н}/labels/{urllib.parse.quote(МІТКА)}")
    if код != 200:
        return False, f"#{н}: мітку «{МІТКА}» не знято ({код})"
    api.запит("POST", f"{р}/issues/{н}/comments", {"body": f"CI самозлиття: мітку «{МІТКА}» знято — {пояснення}."})
    return True, f"#{н}: мітку «{МІТКА}» знято — {пояснення}"


def прибрати_старі(api, старі):
    """PR із застарілою міткою (`обійти`): мітку знято й сказано чому, щоб вона не висіла й не мовчала. Звіряє PR
    знову: закритий, змінена голова чи нема мітки — не чіпає (нова голова — нове рішення диспетчера)."""
    рядки = []
    for к in старі:
        н = int(к["номер"])
        код, pr, _ = api.запит("GET", f"/repos/{api.р}/pulls/{н}")
        if код != 200 or pr.get("state") != "open" or pr["head"]["sha"] != к["голова"]:
            рядки.append(f"#{н}: мітку не чіпаю — PR змінився після рішення")
            continue
        if МІТКА in {(м or {}).get("name") for м in pr.get("labels") or []}:
            рядки.append(зняти_мітку(api, н, "голова з'явилась знову після мітки (новий коміт, rebase чи force-push); "
                                              "рішення знову за диспетчером — постав мітку ще раз")[1])
    return рядки


def злити(api, кандидати):
    """Кандидати [{номер, голова, спосіб?}] → (злито [(номер, sha злиття, код?)], перед, рядки підсумку).

    `перед` — перший батько першого злиття (main до нього): база для робочих процесів `main` після злиття."""
    р = f"/repos/{api.р}"
    перед, злито, рядки = "", [], []
    for к in кандидати:
        н, голова = int(к["номер"]), к["голова"]
        код, pr, _ = api.запит("GET", f"{р}/pulls/{н}")
        if код != 200 or pr.get("state") != "open" or pr.get("draft") or pr["head"]["sha"] != голова:
            рядки.append(f"#{н}: не злито — PR змінився після рішення (стан, чернетка чи голова)")
            if (код == 200 and pr.get("state") == "open" and к.get("спосіб") == "мітка" and pr["head"]["sha"] != голова
                    and МІТКА in {(м or {}).get("name") for м in pr.get("labels") or []}):
                рядки.append(зняти_мітку(api, н, "голова змінилась після мітки; постав мітку ще раз на новій голові")[1])
            continue
        тіло = {"sha": голова, "merge_method": "squash", "commit_title": f"{pr['title']} (#{н})"}
        спосіб = к.get("спосіб", "документ")
        код_pr = спосіб in {"код", "мітка"}
        if спосіб == "мітка" and МІТКА not in {(м or {}).get("name") for м in pr.get("labels") or []}:
            рядки.append(f"#{н}: не злито — мітку «{МІТКА}» знято після рішення")
            continue
        if спосіб == "код":
            відмова = _умови_pr(pr)
            if not відмова:
                try:
                    відмова = _файли_коду(pr, api.усі(f"{р}/pulls/{н}/files"))
                except (RuntimeError, OSError, ValueError, KeyError, TypeError):
                    відмова = "не вдалося прочитати файли PR"
            if not відмова:
                так, чому = _рецензії_коду(api, н, голова, к.get("початок_ci"))
                if not так:
                    відмова = чому
            if відмова:
                рядки.append(f"#{н}: не злито — {відмова}")
                continue
        if код_pr:
            тіло["commit_message"] = pr.get("body") or ""
        код, відповідь, _ = api.запит("PUT", f"{р}/pulls/{н}/merge", тіло)
        if код == 200 and (відповідь or {}).get("merged"):
            злито.append((н, відповідь["sha"], код_pr))
            if МІТКА in {(м or {}).get("name") for м in pr.get("labels") or []}:
                api.запит("DELETE", f"{р}/issues/{н}/labels/{urllib.parse.quote(МІТКА)}")
            рядки.append(f"#{н}: злито squash з голови {голова} → {відповідь['sha']}" + (" (за міткою)" if спосіб == "мітка" else " (код)" if спосіб == "код" else ""))
        else:
            рядки.append(f"#{н}: не злито — {код} {(відповідь or {}).get('message', '')}")
    if злито:
        код, коміт, _ = api.запит("GET", f"{р}/commits/{злито[0][1]}")
        батьки = (коміт or {}).get("parents") or [] if код == 200 else []
        перед = батьки[0]["sha"] if батьки else ""
    return злито, перед, рядки


