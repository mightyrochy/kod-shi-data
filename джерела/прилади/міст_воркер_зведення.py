"""Зведення прогонів `міст_воркер_дослід.js` (крок 4.1-А): медіани ДО/ПІСЛЯ за прогонами — підйом, Python за
ендпойнтами, передача (обіг − Python у воркері), розбір JSON у головному потоці, long tasks і пульс головного потоку.

  python3 джерела/прилади/міст_воркер_зведення.py <тека прогону 1> [<тека прогону 2> …]

Друкує таблиці Markdown; кожна тека — вихід одного запуску (підтеки `до/` і `після/` з `час.json`)."""
import json, os, signal, statistics, sys


def медіана(з):
    з = [x for x in з if x is not None]
    return statistics.median(з) if з else None


def прочитати(теки, режим):
    return [json.load(open(os.path.join(т, режим, 'час.json'), encoding='utf-8')) for т in теки]


def за_ендпойнтами(прогін):
    """ім → [викликів, Python мс, обіг мс, розбір мс, байтів входу, байтів виходу] одного прогону"""
    р = {}
    for н, ім, пи, об, роз, код, вх, вих, _тип in прогін['виклики']:
        з = р.setdefault(ім, [0, 0.0, 0.0, 0.0, 0, 0])
        з[0] += 1; з[1] += пи; з[2] += об; з[3] += роз; з[4] += вх; з[5] += вих
    return р


def main():
    signal.signal(signal.SIGPIPE, signal.SIG_DFL)    # `| head` не друкує трасу
    теки = sys.argv[1:]
    if not теки:
        sys.exit(__doc__)
    режими = [р for р in ('до', 'арг', 'після') if all(os.path.isdir(os.path.join(т, р)) for т in теки)]
    пр = {р: прочитати(теки, р) for р in режими}
    назви = {'до': 'ДО (головний, код)', 'арг': 'головний, аргумент', 'після': 'ПІСЛЯ (воркер)'}
    с = lambda мс: '%.2f' % (мс / 1000)
    ряд = lambda назва, ф: print('| %s | %s |' % (назва, ' | '.join(ф(пр[р]) for р in режими)))
    print('Прогонів: %d (медіани)\n' % len(теки))
    print('| | %s |\n|---|%s' % (' | '.join(назви[р] for р in режими), '---|' * len(режими)))
    for к, назва in (('python', 'Python, 124 виклики, с'), ('обіг', 'обіг виклику разом, с'), ('розбір', 'JSON.parse у головному, с')):
        ряд(назва, lambda п, к=к: с(медіана([x['разом'][к] for x in п])))
    ряд('передача (обіг − Python), с', lambda п: с(медіана([x['разом']['обіг'] - x['разом']['python'] for x in п])))
    for к, назва in (('python', 'збір: Python, с'), ('обіг', 'збір: обіг, с')):
        ряд(назва, lambda п, к=к: с(медіана([x['збір'][к] for x in п])))
    ряд('код Python за прогін, МБ', lambda п: '%.2f' % (п[0]['разом']['байтів_коду'] / 1e6))
    ряд('вхід / вихід за прогін, МБ', lambda п: '%.2f / %.2f' % (п[0]['разом']['байтів_входу'] / 1e6, п[0]['разом']['байтів_виходу'] / 1e6))
    for вікно in ('підйом', 'виклики', 'збір'):
        for міра, назва in (('довгі', 'long tasks'), ('пульс', 'пульс > 50 мс')):
            ряд('%s: %s' % (вікно, назва), lambda п, м=міра, в=вікно: '%d шт · %s с · найдовша %d мс' % (
                медіана([x[м][в]['штук'] for x in п]), с(медіана([x[м][в]['мс'] for x in п])),
                медіана([x[м][в]['найдовша'] for x in п])))
    print('\nПідйом, мс (медіана):\n')
    for р in режими:
        ключі = [к for к in пр[р][0]['підйом'] if к not in ('від', 'до')]
        print('- %s: %s' % (назви[р], ', '.join('%s %d' % (к, медіана([x['підйом'][к] for x in пр[р]])) for к in ключі)))
    е = {р: [за_ендпойнтами(x) for x in пр[р]] for р in режими}
    print('\n| Ендпойнт | викликів | %s | передача ПІСЛЯ, мс | розбір у головному, мс | вихід, КБ |\n|---|---|%s---|---|---|'
          % (' | '.join('Python %s, с' % назви[р] for р in режими), '---|' * len(режими)))
    перший = е[режими[0]][0]
    for ім in sorted(перший, key=lambda і: -перший[і][1]):
        print('| %s | %d | %s | %d | %d | %d |' % (
            ім, перший[ім][0], ' | '.join(с(медіана([x[ім][1] for x in е[р]])) for р in режими),
            медіана([x[ім][2] - x[ім][1] for x in е['після']]) if 'після' in е else 0,
            медіана([x[ім][3] for x in е['після']]) if 'після' in е else 0, перший[ім][5] / 1024))
    for x in пр.get('після', []):
        if x.get('покоління') or x.get('поза_порядком'):
            print('\nпокоління: %s · поза порядком: %s' % (json.dumps(x.get('покоління'), ensure_ascii=False),
                                                         json.dumps(x.get('поза_порядком'), ensure_ascii=False)))

if __name__ == '__main__':
    main()
