# -*- coding: utf-8 -*-
"""ЗГОРТАННЯ ДОШКИ: файли `аудит/дошка/**/*.md` → рядки `аудит/БЕКЛОГ.md`, файли видаляє.

ЩО ЦЕ ЛАГОДИТЬ (ПК-2, ПР-1 з `аудит/витрати/аналіз_1518.md` §5, слово власника 18.10 «Пр-1 так»).
Дошку правили 147 зі 150 PR, і кожне злиття робило решту конфліктними: 119 злиттів `main` у гілки.
Тепер PR дошки не чіпає — пише свої нові рядки й зміни стану у файл `аудит/дошка/<гілка>.md`
(гілка `claude/x` → `аудит/дошка/claude/x.md`), а після злиття в `main` CI згортає файли в дошку
тим самим комітом, що збирає `index.html` (`zbirka.yml`).

ФОРМАТ ФАЙЛА (кожен непорожній рядок — одне з чотирьох; будь-що інше — помилка з назвою файлу й рядка):
  | 8510 | джерело | вага | **ВІДКРИТО** · … | …   новий рядок — тим самим рядком таблиці, що в дошці
  стан N: **ЗАКРИТО #PR** · …                      новий вміст клітинки «статус» названого рядка
  заміна | N | … | **ЗАКРИТО #PR** · … | …         запис цілком — коли міняється ще й «доказ» чи інша клітинка
  стан! 5233: **ВІДКРИТО** · …  /  заміна! | 5233 | …    те саме, але ранг знижується свідомо (повернення відкриття)
  # …  /  <!-- … -->  /  | № | … |  /  |---|…       коментар, шапка таблиці — пропускаються

Поля нового рядка й закриття описано в `дошка_поля.py`; --лише-перевірити вимагає їх.
Звичайне згортання лишається сумісним зі старими фрагментами вже відкритих PR.

ЩО РОБИТЬ. Нові рядки вставляються ПЕРЕД останнім пронумерованим рядком дошки, а не після нього: PR, відкриті до
цього способу, додають свої рядки в кінець по-старому, і вставка перед останнім рядком із їхньою — в git не
сусідні зміни (між ними лишається незмінений рядок), тож зливаються без конфлікту. Файли йдуть за найменшим
номером нового рядка, рядки — у порядку файлу. Далі заміни рядків, далі зміни стану: «стан» підміняє лише
клітинку «статус», решта рядка лишається побайтово. У межах одного згортання зміни йдуть від нижчого рангу
до вищого (ВІДКРИТО < ЧАСТКОВО < ЗАКРИТО), тож порядок файлів не робить ЗАКРИТО частковим.

ЩО НЕ МОВЧИТЬ. Номер, зайнятий у дошці чи в іншому файлі іншим рядком; заміна чи зміна стану рядка, якого
нема; два файли, що замінюють той самий рядок; зниження рангу проти дошки без «!»; рядок файлу, що не
належить до чотирьох, — це «ПОМИЛКА <файл>: …». Файл із
помилкою не згортається й не видаляється ні частково, ні цілком (решта файлів згортається), код виходу 1.
Тотожний рядок, що вже є в дошці (PR устиг вписати його й туди), — не помилка: пропущено, у звіті «вже було».

ЗАПУСК (з кореня репозиторію):
    python3 джерела/прилади/згорнути_дошку.py                    # згорнути й видалити файли
    python3 джерела/прилади/згорнути_дошку.py --лише-перевірити  # нічого не писати (перевірка PR)
"""
import os
import re
import sys
from дошка_поля import метадані, перевірити_поля

КОРІНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ДОШКА = os.path.join(КОРІНЬ, 'аудит', 'БЕКЛОГ.md')
ТЕКА = os.path.join(КОРІНЬ, 'аудит', 'дошка')

РЯДОК = re.compile(r'^\| *(\d+) *\|')
СТАН = re.compile(r'^стан(!?) +(\d+) *: *(.*\S)\s*$')
ЗАМІНА = re.compile(r'^заміна(!?) +(\| *(\d+) *\|.*)$')
ПРОПУСК = re.compile(r'^(#|<!--|\| *№|\|[ :|-]*$)')
РОЗДІЛЮВАЧ = re.compile(r'(?<!\\)\|')


def ранг(клітинка):
    t = клітинка.replace('*', '').strip()
    return 3 if t.startswith('ЗАКРИТО') else 2 if t.startswith('ЧАСТКОВО') else 1


def межі_стану(рядок):
    """Межі клітинки «статус» — між 3-м і 4-м неекранованими `|`; None, якщо розділювачів менше п'яти."""
    п = [м.start() for м in РОЗДІЛЮВАЧ.finditer(рядок)]
    return (п[3] + 1, п[4]) if len(п) > 4 else None


def ранг_рядка(рядок):
    м = межі_стану(рядок)
    return ранг(рядок[м[0]:м[1]]) if м else 1


def прочитати(шлях, назва, суворо=False):
    """→ (нові рядки [(номер, рядок)], заміни [(номер, рядок, свідомо)], зміни стану [(номер, текст, свідомо)], помилки)."""
    нові, заміни, зміни, помилки = [], [], [], []
    with open(шлях, encoding='utf-8') as f:
        вміст = f.read().split('\n')
    for н, р in enumerate(вміст, 1):
        р = р.rstrip('\r')
        де = f'{назва}:{н}'
        if not р.strip() or ПРОПУСК.match(р):
            continue
        м = РЯДОК.match(р)
        з = ЗАМІНА.match(р)
        с = СТАН.match(р)
        рядок = м and р or з and з[2]
        if суворо and (рядок or с):
            текст = рядок or с[3]
            закрито = (ранг_рядка(рядок) if рядок else ранг(текст)) > 1
            if рядок and межі_стану(рядок):
                від, до = межі_стану(рядок)
                вади = перевірити_поля(рядок[:від] + рядок[до:], новий=bool(м))
                вади += перевірити_поля(рядок[від:до], закрито=закрито)
            else:
                вади = перевірити_поля(текст, закрито=закрито)
            помилки += [f'{де}: {п}' for п in вади]
        if рядок and not межі_стану(рядок):
            помилки.append(f'{де}: у рядку менше п\'яти `|` — нема клітинки «статус»')
        elif м:
            нові.append((м[1], р))
        elif з:
            заміни.append((з[3], з[2], bool(з[1])))
        elif с and РОЗДІЛЮВАЧ.search(с[3]):
            помилки.append(f'{де}: у новому стані рядка {с[2]} неекранований `|` — розірве таблицю')
        elif с:
            зміни.append((с[2], с[3], bool(с[1])))
        else:
            помилки.append(f'{де}: не «| N | …», не «заміна | N | …», не «стан N: …» і не коментар: {р[:60]}')
    return нові, заміни, зміни, помилки


def зібрати_файли():
    шляхи = []
    for кат, _, імена in os.walk(ТЕКА):
        шляхи += [os.path.join(кат, і) for і in імена if і.endswith('.md')]
    return sorted(шляхи)


def згорнути(лише_перевірити=False):
    with open(ДОШКА, encoding='utf-8') as f:
        рядки = f.read().split('\n')
    дошка = {РЯДОК.match(р)[1]: і for і, р in enumerate(рядки) if РЯДОК.match(р)}
    помилки, файли = [], {}
    for шлях in зібрати_файли():
        назва = os.path.relpath(шлях, КОРІНЬ)
        # Суворий контракт лише для PR. Згортання приймає також фрагменти,
        # створені до появи полів: їхній формат уже перевірив попередній CI.
        нові, заміни, зміни, пом = прочитати(шлях, назва, суворо=лише_перевірити)
        помилки += пом
        if not пом:
            файли[назва] = (шлях, нові, заміни, зміни)
    справні = set(файли)

    # Номер: зайнятий іншим рядком (у дошці чи в іншому файлі) — помилка кожному, хто його заявив.
    заявники = {}
    for назва in sorted(справні):
        for номер, р in файли[назва][1]:
            заявники.setdefault(номер, []).append((назва, р))
    for номер, з in sorted(заявники.items(), key=lambda п: int(п[0])):
        варіанти = {р for _, р in з} | ({рядки[дошка[номер]]} if номер in дошка else set())
        if len(варіанти) > 1:
            хто = ', '.join(н for н, _ in з) + (' і дошка' if номер in дошка else '')
            for н in {н for н, _ in з}:
                помилки.append(f'{н}: номер {номер} зайнятий іншим рядком ({хто})')
                справні.discard(н)

    # Заміна й зміна стану: ціль є в дошці чи в нових рядках справного файлу, ранг не нижчий за початковий
    # (без «!»), рядок замінює один файл. Файл, що випав, може прибрати ціль іншому, тож — до нерухомої точки.
    while True:
        нові_рядки = {н: р for назва in справні for н, р in файли[назва][1]}
        замінники = {}
        for назва in sorted(справні):
            for номер, _, _ in файли[назва][2]:
                замінники.setdefault(номер, set()).add(назва)
        погані = set()
        for назва in sorted(справні):
            if лише_перевірити:
                for номер, текст in файли[назва][1] + [(н, р) for н, р, _ in файли[назва][2]]:
                    від, до = межі_стану(текст)
                    попередник = метадані(текст[:від] + текст[до:]).get('попередник', 'ні')
                    if попередник == 'ні':
                        continue
                    батько = попередник.split()[-1]
                    попередній = рядки[дошка[батько]] if батько in дошка else нові_рядки.get(батько)
                    if батько == номер or попередній is None:
                        помилки.append(f'{назва}: поле попередник: рядок {номер}, {батько} — сам рядок або відсутній')
                        погані.add(назва)
                    elif попередник.startswith('повернення') and ранг_рядка(попередній) != 3:
                        помилки.append(f'{назва}: поле попередник: рядок {номер}, {батько} не закритий')
                        погані.add(назва)
            дії = [(н, р, с, 'заміна') for н, р, с in файли[назва][2]] + [(н, т, с, 'стан') for н, т, с in файли[назва][3]]
            for номер, текст, свідомо, вид in дії:
                початковий = рядки[дошка[номер]] if номер in дошка else нові_рядки.get(номер)
                if початковий is None:
                    помилки.append(f'{назва}: {вид} рядка {номер}, якого нема ні в дошці, ні в нових рядках справних файлів')
                    погані.add(назва)
                elif вид == 'заміна' and len(замінники[номер]) > 1:
                    помилки.append(f'{назва}: рядок {номер} замінюють кілька файлів ({", ".join(sorted(замінники[номер]))})')
                    погані.add(назва)
                elif not свідомо and (ранг_рядка(текст) if вид == 'заміна' else ранг(текст)) < ранг_рядка(початковий):
                    помилки.append(f'{назва}: {вид} рядка {номер} знижує ранг проти дошки (свідоме повернення — «{вид}!»)')
                    погані.add(назва)
                elif лише_перевірити and вид == 'заміна':
                    від, до = межі_стану(початковий)
                    попередні = метадані(початковий[:від] + початковий[до:])
                    if 'дата' in попередні:
                        від, до = межі_стану(текст)
                        зовні = текст[:від] + текст[до:]
                        вади = перевірити_поля(зовні, новий=True)
                        if метадані(зовні).get('дата') != попередні['дата']:
                            вади.append('поле дата: заміна має зберігати дату появи')
                        помилки += [f'{назва}: {п}' for п in вади]
                        if вади:
                            погані.add(назва)
        if not погані:
            break
        справні -= погані

    # Нові рядки — перед останнім пронумерованим (див. докстрінг); файли — за найменшим номером нового рядка.
    порядок = sorted(справні, key=lambda н: (min([int(х) for х, _ in файли[н][1]] or [10 ** 9]), н))
    додано, вже_було, мають = [], 0, set(дошка)
    for назва in порядок:
        for номер, р in файли[назва][1]:
            if номер in мають:
                вже_було += 1
            else:
                мають.add(номер)
                додано.append(р)
    кінець = max(дошка.values())
    рядки[кінець:кінець] = додано
    індекс = {РЯДОК.match(р)[1]: і for і, р in enumerate(рядки) if РЯДОК.match(р)}
    заміни = [(н, р) for назва in порядок for н, р, _ in файли[назва][2]]
    for номер, р in заміни:
        рядки[індекс[номер]] = р
    # Зміни стану — від нижчого рангу до вищого, при рівному — у порядку файлів.
    зміни = sorted((ранг(т), порядок.index(назва), н, т) for назва in порядок for н, т, _ in файли[назва][3])
    for _, _, номер, текст in зміни:
        і = індекс[номер]
        від, до = межі_стану(рядки[і])
        рядки[і] = рядки[і][:від] + ' ' + текст + ' ' + рядки[і][до:]
    звіт = (f'файлів {len(зібрати_файли())}, згорнуто {len(справні)}; нових рядків {len(додано)}, замін {len(заміни)}, '
            f'змін стану {len(зміни)}, вже було {вже_було}; помилок {len(помилки)}')
    if not лише_перевірити and справні:
        тимчасовий = ДОШКА + '.tmp'
        with open(тимчасовий, 'w', encoding='utf-8') as f:
            f.write('\n'.join(рядки))
        os.replace(тимчасовий, ДОШКА)
        for назва in справні:
            os.remove(файли[назва][0])
        for кат, _, _ in sorted(os.walk(ТЕКА), reverse=True):
            if кат != ТЕКА and not os.listdir(кат):
                os.rmdir(кат)
    return звіт, помилки


if __name__ == '__main__':
    if not os.path.isdir(ТЕКА):
        print('аудит/дошка/ нема — нічого згортати')
        sys.exit(0)
    звіт, помилки = згорнути('--лише-перевірити' in sys.argv)
    print(звіт)
    for п in помилки:
        print('ПОМИЛКА ' + п, file=sys.stderr)
    sys.exit(1 if помилки else 0)
