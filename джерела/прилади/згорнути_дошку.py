"""ЗГОРТАННЯ ДОШКИ: файли `аудит/дошка/**/*.md` → рядки робочої дошки й архіву, файли видаляє.

ЩО ЦЕ ЛАГОДИТЬ (ПК-2, ПР-1 з `аудит/витрати/аналіз_1518.md` §5, слово власника 18.10 «Пр-1 так»).
Дошку правили 147 зі 150 PR, і кожне злиття робило решту конфліктними: 119 злиттів `main` у гілки.
Тепер PR дошки не чіпає — пише свої нові рядки й зміни стану у файл `аудит/дошка/<гілка>.md`
(гілка `claude/x` → `аудит/дошка/claude/x.md`), а після злиття в `main` CI згортає файли в дошку
тим самим комітом, що збирає `index.html` (`zbirka.yml`).

ФОРМАТ ФАЙЛА (кожен непорожній рядок — одне з чотирьох; будь-що інше — помилка з назвою файлу й рядка):
  | 8510 | джерело | вага | **ВІДКРИТО** · … | …   новий рядок — тим самим рядком таблиці, що в дошці
  стан N: **ЗАКРИТО #PR** · …                      новий вміст клітинки «статус» названого рядка
  заміна | N | … | **ЗАКРИТО #PR** · … | …         запис цілком — коли міняється ще й «доказ» чи інша клітинка
  стан! 5233: **ВІДКРИТО** · …  /  заміна! | 5233 | …    те саме, але ранг знижується свідомо (повернення відкриття)
  # …  /  <!-- … -->  /  | № | … |  /  |---|…       коментар, шапка таблиці — пропускаються

Поля нового рядка й закриття та межу номерів описано в `дошка_поля.py`.
--лише-перевірити вимагає ці поля від межі; старі номери й їхні закриття сумісні.
Датований рядок зберігає джерело й хронологію за будь-якого номера. Дату появи зберігає заміна;
свідоме виправлення хибної дати за історією — «заміна!», перевірка хронології лишається обов'язковою.
КОРІНЬ РЯДКА. Новий рядок від `ПЕРШИЙ_НОМЕР_КОРЕНЯ` несе в блоці поза статусом `корінь=<ім'я паспорта>` чи
`корінь=жоден`; ім'я звіряється з паспортами `аудит/корені/*.md`, чий перший рядок «# Корінь …». Старий рядок
отримує корінь заміною (`заміна | N | …` з тим самим рядком і полем), а заміна рядка з коренем його не стирає.
  | 14400 | джерело · факт <!-- дошка: дата=…; рід=…; попередник=ні; механізм=…; корінь=Е2-межі --> | … |

ЩО РОБИТЬ. Нові рядки вставляються ПЕРЕД останнім пронумерованим рядком дошки, а не після нього: PR, відкриті до
цього способу, додають свої рядки в кінець по-старому, і вставка перед останнім рядком із їхньою — в git не
сусідні зміни (між ними лишається незмінений рядок), тож зливаються без конфлікту. Файли йдуть за найменшим
номером нового рядка, рядки — у порядку файлу. Далі заміни рядків, далі зміни стану: «стан» підміняє лише
клітинку «статус», решта рядка лишається побайтово. У межах одного згортання зміни йдуть від нижчого рангу
до вищого (ВІДКРИТО < ЧАСТКОВО < ЗАКРИТО), тож порядок файлів не робить ЗАКРИТО частковим.

АРХІВ. Номери спільні для `аудит/БЕКЛОГ.md`, `аудит/дошка_архів/закрито.md` і `застаріле.md`.
Щойно закриті рядки йдуть у «закрито»; «стан!» повертає рядок з архіву, якщо він уже не закритий.
«Заміна!» повертає рядок, якщо знижує його ранг.
Заміна чи зміна стану за номером, що лишає рядок у тій самій категорії, оновлює його на місці.
САМА ДОШКА. `--лише-перевірити` після згортання ще перевіряє кожен рядок дошки й архівів з блоком полів тим самим `вади_рядка`
(`дошка_поля.py`), що й тижневий зріз `дошка_зріз.py`: рядок, який відкидає зріз, червоний тут — зріз і CI не мають двох
визначень «правильних полів». Рядок лише з `корінь=` — не поле зрізу, а розклад коренів.
ЩО НЕ МОВЧИТЬ. Номер, зайнятий у дошці чи в іншому файлі іншим рядком; заміна чи зміна стану рядка, якого
нема; два файли, що замінюють той самий рядок; зниження рангу проти дошки без «!»; рядок файлу, що не
належить до чотирьох, — це «ПОМИЛКА <файл>: …». Файл із
помилкою не згортається й не видаляється ні частково, ні цілком (решта файлів згортається), код виходу 1.
Тотожний рядок, що вже є в дошці (PR устиг вписати його й туди), — не помилка: пропущено, у звіті «вже було».

ЗАПУСК (з кореня репозиторію):
    python3 джерела/прилади/згорнути_дошку.py                    # згорнути й видалити файли
    python3 джерела/прилади/згорнути_дошку.py --лише-перевірити  # нічого не писати (перевірка PR)
    python3 джерела/прилади/згорнути_дошку.py --help             # довідка без запису на диск (також -h)
"""
import argparse
import os
import re
import sys
import tempfile

# Під `python3 -I` каталог скрипта не в шляху імпорту.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from дошка_поля import (ПЕРШИЙ_СУВОРИЙ_НОМЕР, БЛОК, РОЗДІЛЮВАЧ, РЯДОК, корені_паспортів, метадані,
                        перевірити_поля, ранг, ранг_рядка, межі_стану, вади_рядка, шляхи_дошки, читати_сховище)

КОРІНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ДОШКА = os.path.join(КОРІНЬ, 'аудит', 'БЕКЛОГ.md')
ТЕКА = os.path.join(КОРІНЬ, 'аудит', 'дошка')
КОРЕНІ = os.path.join(КОРІНЬ, 'аудит', 'корені')

СТАН = re.compile(r'^стан(!?) +(\d+) *: *(.*\S)\s*$')
ЗАМІНА = re.compile(r'^заміна(!?) +(\| *(\d+) *\|.*)$')
ПРИЧИНА_АРХІВУ = re.compile(r'^- \*\*(\d+)\.\*\* названих файлів нема: ')
ШАПКА_ТАБЛИЦІ = '| № | джерело | вага | статус | доказ | файли | приймальна команда |\n' + '|---' * 7 + '|\n'
ШАПКА_ЗАКРИТИХ = '# Закриті рядки дошки\n\n' + ШАПКА_ТАБЛИЦІ
ПРОПУСК = re.compile(r'^(#|<!--|\| *№|\|[ :|-]*$)')


def паспорти():
    """Імена паспортів коренів, проти яких звіряється `корінь=`; теки нема (пісочниця) — None, лише форма."""
    return корені_паспортів(КОРЕНІ) if os.path.isdir(КОРЕНІ) else None


def перевірити_рядок(рядок, новий=False, корені=None):
    """Перевіряє повний рядок тим самим `вади_рядка`, що й зріз: джерело датованої появи й хронологію між клітинками.
    Номери до `ПЕРШИЙ_СУВОРИЙ_НОМЕР` без `дата=` не вимагають нових полів і закриття."""
    номер = int(РЯДОК.match(рядок)[1])
    суворий = номер >= ПЕРШИЙ_СУВОРИЙ_НОМЕР
    return вади_рядка(рядок, номер, новий=новий and суворий, корені=корені,
                      закрито=суворий and ранг_рядка(рядок) > 1)


def прочитати(шлях, назва, суворо=False, корені=None):
    """→ (нові рядки [(номер, рядок)], заміни [(номер, рядок, свідомо)], зміни стану [(номер, текст, свідомо)], помилки)."""
    нові, заміни, зміни, помилки = [], [], [], []
    with open(шлях, encoding='utf-8') as f:
        вміст = f.read().split('\n')
    for н, р in enumerate(вміст, 1):
        р = р.rstrip('\r')
        де = f'{назва}:{н}'
        if not р.strip() or ПРОПУСК.match(р):
            continue
        м = РЯДОК.match(р)
        з = ЗАМІНА.match(р)
        с = СТАН.match(р)
        рядок = м and р or з and з[2]
        номер = м[1] if м else з[3] if з else с[2] if с else None
        if суворо and номер:
            if рядок and межі_стану(рядок):
                вади = перевірити_рядок(рядок, новий=bool(м), корені=корені)
            else:
                # Зміна стану перевіряється разом із рештою цільового рядка в згорнути.
                вади = []
            помилки += [f'{де}: {п}' for п in вади]
        if рядок and not межі_стану(рядок):
            помилки.append(f'{де}: у рядку менше п\'яти `|` — нема клітинки «статус»')
        elif м:
            нові.append((м[1], р))
        elif з:
            заміни.append((з[3], з[2], bool(з[1])))
        elif с and РОЗДІЛЮВАЧ.search(с[3]):
            помилки.append(f'{де}: у новому стані рядка {с[2]} неекранований `|` — розірве таблицю')
        elif с:
            зміни.append((с[2], с[3], bool(с[1])))
        else:
            помилки.append(f'{де}: не «| N | …», не «заміна | N | …», не «стан N: …» і не коментар: {р[:60]}')
    return нові, заміни, зміни, помилки


def перевірити_дошку(рядки, корені=None, назва='аудит/БЕКЛОГ.md'):
    """Усі рядки з блоком `<!-- дошка: … -->` (старі без блоку — поза полями): ті самі вади, що бачить зріз."""
    помилки = []
    for р in рядки:
        м = РЯДОК.match(р)
        if м and БЛОК.search(р):
            помилки += [f'{назва}: рядок {м[1]}: {п}' for п in вади_рядка(р, int(м[1]), корені=корені)]
    return помилки


def зібрати_файли():
    шляхи = []
    for кат, _, імена in os.walk(ТЕКА):
        шляхи += [os.path.join(кат, і) for і in імена if і.endswith('.md')]
    return sorted(шляхи)


def розкласти_рядки(шляхи, вміст, розміщення, дошка, додано, повернення):
    """Переносить рядки за остаточним станом і зберігає інші рядки й шапки на місці."""
    робоча, закрито, застаріле = шляхи
    куди = {}
    for номер, рядок in дошка.items():
        if ранг_рядка(рядок) == 3:
            куди[номер] = закрито
        elif розміщення.get(номер) == застаріле and номер not in повернення:
            куди[номер] = застаріле
        else:
            куди[номер] = робоча
    результат = {}
    for шлях, рядки in вміст.items():
        на_місці = []
        останній = None
        for рядок in рядки:
            м = РЯДОК.match(рядок)
            причина = ПРИЧИНА_АРХІВУ.match(рядок) if шлях == застаріле else None
            if м:
                номер = м[1]
                if куди[номер] == шлях:
                    останній = len(на_місці)
                    текст = рядок.rstrip('\r\n')
                    на_місці.append(дошка[номер] + рядок[len(текст):])
            elif not причина or куди.get(причина[1]) == шлях:
                на_місці.append(рядок)
        # Нові номери далі вставляються перед останнім рядком робочої дошки, як до архівізації.
        порядок = додано + [н for н in розміщення if розміщення[н] != шлях]
        перенесені = [дошка[н] + '\n' for н in порядок if куди[н] == шлях]
        if перенесені:
            if шлях == закрито and not на_місці:
                на_місці = [ШАПКА_ЗАКРИТИХ]
            місце = останній if шлях == робоча and останній is not None else len(на_місці)
            if місце and not на_місці[місце - 1].endswith(('\r', '\n')):
                на_місці[місце - 1] += '\n'
            на_місці[місце:місце] = перенесені
        результат[шлях] = на_місці
    return результат


def записати_сховище(до, після):
    """Готує всі записи перед заміною файлів і повертає початковий вміст, якщо заміна не вдалася."""
    тимчасові, записані = {}, []
    try:
        for шлях, рядки in після.items():
            if рядки == до[шлях]:
                continue
            шлях.parent.mkdir(parents=True, exist_ok=True)
            with tempfile.NamedTemporaryFile(dir=шлях.parent, delete=False) as файл:
                тимчасові[шлях] = файл.name
                файл.write(''.join(рядки).encode('utf-8'))
        for шлях, тимчасовий in тимчасові.items():
            був = шлях.exists()
            os.replace(тимчасовий, шлях)
            записані.append((шлях, був))
    except OSError:
        for шлях, був in reversed(записані):
            if був:
                шлях.write_bytes(''.join(до[шлях]).encode('utf-8'))
            else:
                шлях.unlink()
        raise
    finally:
        for тимчасовий in тимчасові.values():
            if os.path.exists(тимчасовий):
                os.unlink(тимчасовий)


def згорнути(лише_перевірити=False):
    """Згортає справні фрагменти в дошку й архіви або перевіряє результат без запису."""
    шляхи = шляхи_дошки(ДОШКА)
    вміст, розміщення, дошка, помилки = читати_сховище(шляхи)
    if помилки:
        return f'помилок {len(помилки)}', помилки
    файли = {}
    корені = паспорти() if лише_перевірити else None
    for шлях in зібрати_файли():
        назва = os.path.relpath(шлях, КОРІНЬ)
        # Перевірка PR вимагає нові поля за межею номера зі спільної схеми.
        # Структура, зайняті номери й переходи стану перевіряються для всіх.
        нові, заміни, зміни, пом = прочитати(шлях, назва, суворо=лише_перевірити, корені=корені)
        помилки += пом
        if not пом:
            файли[назва] = (шлях, нові, заміни, зміни)
    справні = set(файли)

    # Номер: зайнятий іншим рядком (у дошці чи в іншому файлі) — помилка кожному, хто його заявив.
    заявники = {}
    for назва in sorted(справні):
        for номер, р in файли[назва][1]:
            заявники.setdefault(номер, []).append((назва, р))
    for номер, з in sorted(заявники.items(), key=lambda п: int(п[0])):
        варіанти = {р for _, р in з} | ({дошка[номер]} if номер in дошка else set())
        if len(варіанти) > 1:
            хто = ', '.join(н for н, _ in з) + (' і дошка' if номер in дошка else '')
            for н in {н for н, _ in з}:
                помилки.append(f'{н}: номер {номер} зайнятий іншим рядком ({хто})')
                справні.discard(н)

    # Заміна й зміна стану: ціль є в дошці чи в нових рядках справного файлу, ранг не нижчий за початковий
    # (без «!»), рядок замінює один файл. Файл, що випав, може прибрати ціль іншому, тож — до нерухомої точки.
    while True:
        нові_рядки = {н: р for назва in справні for н, р in файли[назва][1]}
        замінені_рядки = {н: р for назва in справні for н, р, _ in файли[назва][2]}
        замінники = {}
        for назва in sorted(справні):
            for номер, _, _ in файли[назва][2]:
                замінники.setdefault(номер, set()).add(назва)
        погані = set()
        for назва in sorted(справні):
            if лише_перевірити:
                for номер, текст in файли[назва][1] + [(н, р) for н, р, _ in файли[назва][2]]:
                    від, до = межі_стану(текст)
                    попередник = метадані(текст[:від] + текст[до:]).get('попередник', 'ні')
                    if попередник == 'ні':
                        continue
                    батько = попередник.split()[-1]
                    попередній = дошка.get(батько, нові_рядки.get(батько))
                    if батько == номер or попередній is None:
                        помилки.append(f'{назва}: поле попередник: рядок {номер}, {батько} — сам рядок або відсутній')
                        погані.add(назва)
                    elif попередник.startswith('повернення') and ранг_рядка(попередній) != 3:
                        помилки.append(f'{назва}: поле попередник: рядок {номер}, {батько} не закритий')
                        погані.add(назва)
            дії = [(н, р, с, 'заміна') for н, р, с in файли[назва][2]] + [(н, т, с, 'стан') for н, т, с in файли[назва][3]]
            for номер, текст, свідомо, вид in дії:
                початковий = дошка.get(номер, нові_рядки.get(номер))
                if початковий is None:
                    помилки.append(f'{назва}: {вид} рядка {номер}, якого нема ні в дошці, ні в нових рядках справних файлів')
                    погані.add(назва)
                elif вид == 'заміна' and len(замінники[номер]) > 1:
                    помилки.append(f'{назва}: рядок {номер} замінюють кілька файлів ({", ".join(sorted(замінники[номер]))})')
                    погані.add(назва)
                elif not свідомо and (ранг_рядка(текст) if вид == 'заміна' else ранг(текст)) < ранг_рядка(початковий):
                    помилки.append(f'{назва}: {вид} рядка {номер} знижує ранг проти дошки (свідоме повернення — «{вид}!»)')
                    погані.add(назва)
                elif лише_перевірити:
                    від, до = межі_стану(початковий)
                    попередні = метадані(початковий[:від] + початковий[до:])
                    вади = []
                    if вид == 'стан':
                        основа = замінені_рядки.get(номер, початковий)
                        від, до = межі_стану(основа)
                        вади = перевірити_рядок(основа[:від] + ' ' + текст + ' ' + основа[до:], корені=корені)
                    else:
                        від, до = межі_стану(текст)
                        зовні = текст[:від] + текст[до:]
                        if 'дата' in попередні:
                            вади = перевірити_поля(зовні, новий=True, рядок=текст, номер=int(номер), корені=корені)
                            if метадані(зовні).get('дата') != попередні['дата'] and not свідомо:
                                вади.append('поле дата: заміна має зберігати дату появи')
                        else:
                            вади = перевірити_поля(зовні, рядок=текст, корені=корені)
                        # Корінь рядка заміна може змінити, але не стерти: інакше давня копія рядка мовчки знімає розклад.
                        if 'корінь' in попередні and 'корінь' not in метадані(зовні):
                            вади.append('поле корінь: заміна має зберігати корінь рядка')
                    помилки += [f'{назва}: рядок {номер}: {п}' for п in вади]
                    if вади:
                        погані.add(назва)
        if not погані:
            break
        справні -= погані

    # Нові рядки — перед останнім пронумерованим (див. докстрінг); файли — за найменшим номером нового рядка.
    порядок = sorted(справні, key=lambda н: (min([int(х) for х, _ in файли[н][1]] or [10 ** 9]), н))
    додано, вже_було = [], 0
    for назва in порядок:
        for номер, р in файли[назва][1]:
            if номер in дошка:
                вже_було += 1
            else:
                дошка[номер] = р
                додано.append(номер)
    заміни = [(н, р, свідомо) for назва in порядок for н, р, свідомо in файли[назва][2]]
    повернення = {н for н, р, свідомо in заміни if свідомо and ранг_рядка(р) < ранг_рядка(дошка[н])}
    for номер, р, _ in заміни:
        дошка[номер] = р
    # Зміни стану — від нижчого рангу до вищого, при рівному — у порядку файлів.
    зміни = sorted((ранг(т), і, н, т, свідомо)
                   for і, назва in enumerate(порядок) for н, т, свідомо in файли[назва][3])
    for _, _, номер, текст, свідомо in зміни:
        рядок = дошка[номер]
        від, до = межі_стану(рядок)
        дошка[номер] = рядок[:від] + ' ' + текст + ' ' + рядок[до:]
        if свідомо:
            повернення.add(номер)
    після = розкласти_рядки(шляхи, вміст, розміщення, дошка, додано, повернення)
    if лише_перевірити:
        for шлях, рядки in після.items():
            назва = 'аудит/БЕКЛОГ.md' if шлях == шляхи[0] else os.path.relpath(шлях, КОРІНЬ)
            помилки += перевірити_дошку(рядки, корені, назва)
    звіт = (f'файлів {len(зібрати_файли())}, згорнуто {len(справні)}; нових рядків {len(додано)}, замін {len(заміни)}, '
            f'змін стану {len(зміни)}, вже було {вже_було}; помилок {len(помилки)}')
    if not лише_перевірити and (справні or not помилки):
        записати_сховище(вміст, після)
        for назва in справні:
            os.remove(файли[назва][0])
        for кат, _, _ in sorted(os.walk(ТЕКА), reverse=True):
            if кат != ТЕКА and not os.listdir(кат):
                os.rmdir(кат)
    return звіт, помилки


def розібрати_аргументи(аргументи=None):
    """Розбирає аргументи командного рядка: без аргументів — згортання, `--лише-перевірити` — лише перевірка."""
    парсер = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
        allow_abbrev=False,
    )
    парсер.add_argument(
        '--лише-перевірити',
        action='store_true',
        dest='лише_перевірити',
        help='перевірити файли аудит/дошка/, саму дошку й архіви без запису на диск',
    )
    return парсер.parse_args(аргументи)


