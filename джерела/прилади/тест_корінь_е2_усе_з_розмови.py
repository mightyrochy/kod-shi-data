# -*- coding: utf-8 -*-
"""Синтетичні перевірки виявлення подій і повного шляху Е2, без продукту/API."""
import tempfile
from pathlib import Path
import unittest

from е2_обробники import граф
from корінь_е2_усе_з_розмови import вимір, відбиток_контексту


class ПриладЕ2(unittest.TestCase):
    """Звіряє розриви й повні шляхи на мінімальних деревах джерел."""

    def дані(self, код='', html='', інші=None):
        """Парсить тимчасовий продукт тим самим Acorn, що й основна лічба."""
        with tempfile.TemporaryDirectory(prefix='е2-тест-') as тека:
            корінь = Path(тека)
            (корінь / 'джерела').mkdir()
            for файл, текст in {'джерела/дія.js': код, 'джерела/показ.html': html, **(інші or {})}.items():
                шлях = корінь / файл
                шлях.parent.mkdir(parents=True, exist_ok=True)
                шлях.write_text(текст, encoding='utf-8')
            return граф(корінь)

    def лічба(self, код='', html='', інші=None):
        """Повертає вимір без ручного словника винятків."""
        return вимір(self.дані(код, html, інші))

    def test_без_інструмента(self):
        """Видима дія без виклику моделлю є одним місцем."""
        р = self.лічба('function дія(х){return х;} кнопка.onclick=()=>дія(поле.value);')
        self.assertEqual([м['бракує'] for м in р['місця']], [['інструмента']])

    def test_повний_шлях(self):
        """Модель передає вхід у спільну функцію й кладе її результат у чат."""
        р = self.лічба('''function дія(х){return {текст:х};} кнопка.onclick=()=>дія(поле.value);
          async function розмоваШаромП(хід){const р=await дія(хід.значення); ЧАТ_П.push({текст:р});}''')
        self.assertEqual(р['місця'], [])

    def test_немає_передавання(self):
        """Виклик з константою не передає бажання людини."""
        р = self.лічба('''function дія(х){return х;} кнопка.onclick=()=>дія(поле.value);
          function розмоваШаромП(хід){const р=дія('старе'); ЧАТ_П.push({текст:р});}''')
        self.assertEqual(р['місця'][0]['бракує'], ['передавання з розмови'])

    def test_окремий_екран(self):
        """Результат на іншому екрані не дорівнює результату в чаті."""
        р = self.лічба('''function дія(х){return х;} кнопка.onclick=()=>дія(поле.value);
          function розмоваШаромП(хід){const р=дія(хід.х); екран.textContent=р;}''')
        self.assertEqual(р['місця'][0]['бракує'], ['показу результату'])

    def test_стороння_репліка(self):
        """Порожнє підтвердження іншого ходу не маскує загублений результат."""
        р = self.лічба('''function дія(х){return х;} кнопка.onclick=()=>дія(поле.value);
          function розмоваШаромП(хід){дія(хід.х); ЧАТ_П.push({текст:хід.текст});}''')
        self.assertEqual(р['місця'][0]['бракує'], ['показу результату'])

    def test_повернення_обгортки(self):
        """Результат зберігається через async-обгортку й перейменування."""
        р = self.лічба('''function дія(х){return х;} кнопка.onclick=()=>дія(поле.value);
          async function адаптер(х){const відповідь=await дія(х); return {дані:відповідь};}
          async function розмоваШаромП(хід){const а=await адаптер(хід.х);const б=а; ЧАТ_П.push({картка:б});}''')
        self.assertEqual(р['місця'], [])

    def test_окремий_показувач(self):
        """Аргумент результату доходить у функцію, що додає репліку."""
        р = self.лічба('''function дія(х){return х;} кнопка.onclick=()=>дія(поле.value);
          function показати(результат){ЧАТ_П.push({картка:результат});}
          function розмоваШаромП(хід){const р=дія(хід.х);показати(р);}''')
        self.assertEqual(р['місця'], [])

    def test_результат_усередині_дії(self):
        """Дія може сама показувати свій результат у розмові."""
        р = self.лічба('''function дія(х){ЧАТ_П.push({текст:х});} кнопка.onclick=()=>дія(поле.value);
          function розмоваШаромП(хід){дія(хід.х);}''')
        self.assertEqual(р['місця'], [])

    def test_фабрика_чипів(self):
        """Передані фабриці замикання стають окремими входами в дії."""
        р = self.лічба('''function діяА(){return 1;} function діяБ(){return 2;}
          function чип(дія){const к={};к.onclick=дія; return к;}
          чип(()=>діяА()); чип(()=>діяБ());''')
        self.assertEqual(len(р['місця']), 2)
        self.assertEqual(len(р['обробники']), 2)

    def test_передавання_через_дві_фабрики(self):
        """Нерухома точка розкриває й кілька рівнів передавання функцій."""
        р = self.лічба('''function дія(){return 1;} function чип(дія){к.onclick=дія;}
          function плитка(виконати){чип(виконати);} плитка(()=>дія());''')
        self.assertEqual(len(р['місця']), 1)
        self.assertIn('дія', р['місця'][0]['функція'])

    def test_кнопка_з_розмови(self):
        """Селектор зв'язує динамічний onclick із тією самою кнопкою UI."""
        р = self.лічба('''function дія(){return 1;} $('зібрати').onclick=()=>дія();
          function розмоваШаромП(хід){const к=$('зібрати'); const р=к.onclick();ЧАТ_П.push({картка:р});}''')
        self.assertEqual(р['місця'], [])

    def test_html_атрибут(self):
        """Вбудовані атрибути читаються з HTML зі своїми рядками."""
        р = self.лічба('function дія(х){return х;}', '<p>текст</p>\n<button onclick="дія(&quot;а&quot;)">дія</button>')
        self.assertEqual(len(р['місця']), 1)
        self.assertEqual(р['обробники'][0]['обробник'], 'джерела/показ.html:2')

    def test_html_шаблон_js(self):
        """Динамічно створена розмітка з подією теж входить до обсягу."""
        р = self.лічба('''function дія(){return 1;} контейнер.innerHTML=`<button onclick="дія()">Дія</button>`;''')
        self.assertEqual(len(р['місця']), 1)

    def test_setattribute(self):
        """Реєстрація кодом атрибута не губиться."""
        р = self.лічба('''function дія(){return 1;} к.setAttribute('onclick', 'дія()');''')
        self.assertEqual(len(р['місця']), 1)

    def test_усі_глибини(self):
        """Сканер не обмежується показ/*.js; тестові й службові джерела відділені."""
        р = self.лічба(інші={'джерела/нова/глибока/форма.js': 'function дія(){return 1;} к.onclick=дія;',
            'джерела/проби/хибна.js': 'інша.onclick=()=>стороння();',
            'джерела/тест_форма.js': 'інша.onclick=()=>стороння();'})
        self.assertEqual(len(р['місця']), 1)
        self.assertEqual(len(р['файли']), 3)

    def test_області_імен(self):
        """Однакові назви різних локальних функцій не доводять спільність."""
        р = self.лічба('''(function(){function дія(х){return х;}к.onclick=()=>дія(поле.value);})();
          function розмоваШаромП(хід){function дія(х){return х;} const р=дія(хід.х);ЧАТ_П.push({текст:р});}''')
        self.assertEqual(р['місця'][0]['бракує'], ['інструмента'])

    def test_дедуплікація(self):
        """Дві кнопки до однієї функції — одне місце."""
        р = self.лічба('''function дія(х){return х;} а.onclick=()=>дія(поле.value); б.onchange=()=>дія(інше.value);''')
        self.assertEqual(len(р['місця']), 1)
        self.assertEqual(len(р['місця'][0]['інтерфейс']), 2)

    def test_події_й_псевдонім(self):
        """Toggle, keyup та обчислена назва події читаються разом із псевдонімом."""
        р = self.лічба('''function дія(){return 1;} const виклик=дія; к.addEventListener('toggle',виклик);
          б['on'+'keyup']=виклик;''')
        self.assertEqual(len(р['місця']), 1)
        self.assertEqual(len(р['обробники']), 2)

    def test_реєстрація_не_виклик(self):
        """Створення UI з розмови не виконує його бізнес-обробник."""
        р = self.лічба('''function дія(х){return х;} кнопка.onclick=()=>дія(поле.value);
          function розмоваШаромП(хід){інша.onclick=()=>дія(хід.х);ЧАТ_П.push({текст:хід.текст});}''')
        self.assertTrue(all(м['бракує']==['інструмента'] for м in р['місця']))

    def test_зупинка_на_екрані(self):
        """Побічне читання під час рендера не стає інструментом моделі."""
        р = self.лічба('''function дія(){return 1;}к.onclick=()=>дія();
          function малюватиЕкран(){дія();} function розмоваШаромП(хід){малюватиЕкран();ЧАТ_П.push({текст:хід.текст});}''')
        self.assertEqual(р['місця'][0]['бракує'], ['інструмента'])

    def test_нове_без_словника(self):
        """Новий невідомий обробник додає кандидата, а не зникає зі звіту."""
        р = self.лічба('к.onclick=()=>{ПРОФІЛЬ.імя=поле.value;};')
        self.assertEqual(len(р['місця']), 1)
        self.assertEqual(р['невідомих'], 1)

    def test_виключення_і_зміна_помічника(self):
        """Виключення вигляду не переживає зміну функції, яку воно кличе."""
        д = self.дані('function тема(){екран.className="темна";} к.onclick=()=>тема();')
        ф = д['функції'][д['обробники'][0]['ціль']]
        ключ = ф['файл']+':'+ф['відбиток']
        с = {'дії':{},'обробники':{ключ:{'не_місце':'Тема — вигляд.', 'контекст':відбиток_контексту(д['функції'],ф['ід'])}}}
        self.assertEqual(вимір(д,с)['місця'], [])
        зм = self.дані('function тема(){ПРОФІЛЬ.імя=поле.value;} к.onclick=()=>тема();')
        self.assertEqual(len(вимір(зм,с)['місця']), 1)

    def test_нерозкритий_обробник(self):
        """Нерозкритий callback — помилка, а не зелений нуль."""
        with self.assertRaisesRegex(ValueError, 'не розкрито'):
            self.лічба('к.onclick=невідома;')

    def test_підтвердження_спільного_стану(self):
        """Текст застосованого стану доводиться спільним джерелом даних."""
        for стороння in (False, True):
            with self.subTest(стороння=стороння):
                код = '''function зберегти(){} к.onclick=()=>зберегти();
                  function застосувати(стан){зберегти();}
                  function розмоваШаромП(хід){const пш=містП({паспорт_з:хід});
                    застосувати(пш.паспорт);ЧАТ_П.push({текст:ТЕКСТ});}'''
                код = код.replace('ТЕКСТ', 'хід.старе' if стороння else 'пш.текст')
                д = self.дані(код)
                ф = д['функції'][д['обробники'][0]['ціль']]
                с = {'обробники': {ф['файл']+':'+ф['відбиток']:{'дії':['стан']}}, 'дії': {'стан': {
                    'назва':'Змінити стан', 'функція':'зберегти', 'файл':'джерела/дія.js', 'вхід':[],
                    'підтвердження_стану': {'розмова':'розмоваШаромП','джерело':'містП',
                        'поле':'паспорт_з','адаптер':'застосувати'}}}}
                self.assertEqual(len(вимір(д,с)['місця']), int(стороння))

    def test_синтаксична_помилка(self):
        """Пошкоджений JS не пропускається мовчки."""
        import subprocess
        with self.assertRaises(subprocess.CalledProcessError):
            self.лічба('function {')

    def test_стан_форми_не_дорівнює_входу(self):
        """Випадкове збереження старої форми не доводить зміни даних із розмови."""
        for записати in (False, True):
            with self.subTest(записати=записати):
                код = '''function зберегти(){return $('імя').value;} к.onclick=()=>зберегти();
                  function розмоваШаромП(хід){ЗАПИС const р=зберегти();ЧАТ_П.push({текст:р});}'''
                код = код.replace('ЗАПИС', "$('імя').value=хід.імя;" if записати else '')
                д = self.дані(код)
                ф = д['функції'][д['обробники'][0]['ціль']]
                с = {'обробники': {ф['файл']+':'+ф['відбиток']:{'дії':['форма']}}, 'дії': {'форма': {
                    'назва':'Зберегти форму', 'функція':'зберегти', 'файл':'джерела/дія.js',
                    'вхід':[], 'вхід_поля':['імя']}}}
                р = вимір(д,с)
                self.assertEqual(len(р['місця']), int(not записати))
                if not записати:
                    self.assertEqual(р['місця'][0]['бракує'], ['передавання з розмови'])


if __name__ == '__main__':
    unittest.main(verbosity=2)
