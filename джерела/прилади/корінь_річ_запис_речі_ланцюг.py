"""Свідки шляху об'єкта до файлової межі каталогу.

Граф переносить тотожність об'єкта через аргументи, повернення й копії полів.
Вкладення проходиться від серіалізованого запису вниз; контейнер угору записом
не стає. Контракти XML і журналу описують формат файлової межі, не ключі речі.
"""
from collections import deque
import re


ФАЙЛ_КАТАЛОГУ = re.compile(
    r"(?:^|[/\\])(?:catalog|каталог)(?:_(?:повний|жіночий|чоловічий|стенд|brief|записи_v1))?"
    r"\.(?:xml|json|jsonl)(?:\.gz)?$", re.I)
ФАЙЛ_ЖНИВ = re.compile(r"(?:^|[/\\])сирі[/\\][^/\\]+\.jsonl(?:\.gz)?$", re.I)

# (модуль, функція): (параметр колекції, параметр файла, шлях у форматі).
# Контракт береться лише при наявності файлового write у тілі функції.
ЗАПИСУВАЧІ = {
    ("жниварка", "записати_каталог"): (0, 1, ("*",)),
    ("складальник", "писати_записи"): (1, 2, ("*",)),
}


def вирази(е):
    """Обходить вираз разом із генераторами включень."""
    if е is None:
        return
    yield е
    if е.k == "comp":
        for _, ітер, умови in е.v:
            yield from вирази(ітер)
            for у in умови:
                yield from вирази(у)
    for а in е.a:
        yield from вирази(а)


class Ланцюги:
    """Зберігає файлові якорі та ребра переносу кожного окремого об'єкта."""

    def __init__(self, аналіз):
        self.а = аналіз
        self.переходи = {}
        self.якорі = {}
        self.читання = {}
        self.області = {}
        self.функції = {ф.fid: ф for ф in аналіз.функції}
        self.місця = {}
        self.докази = {}
        self.стандарти = set()
        self.переліки = {}
        self.сирі_читачі = {}
        self.сирі_писачі = {}
        self.залежності = {}
        self.нащадки = {}
        self.літерали = {}
        for ф in аналіз.функції:
            for оп in ф.stmts:
                for е in вирази(оп.val):
                    if е.k == "str":
                        self.літерали.setdefault(е.v, []).append((ф.file, е.line))

    def створено(self, о, ф):
        """Запам'ятовує область створення, без визнання записом."""
        self.області.setdefault(о.id, ф.fid)

    def ребро(self, о, звідки, куди, місце):
        """Фіксує передачу цього об'єкта аргументом чи поверненням."""
        self.переходи.setdefault(о.id, {}).setdefault(звідки, set()).add((куди, місце))

    def перенести(self, вал, звідки, куди, місце):
        """Передає також вкладені об'єкти, які справді лежать у значенні."""
        if not self.а.збирати_переходи:
            return
        потрібні = set()
        for о in вал:
            if hasattr(о, "пол"):
                потрібні.update(self.нащадки.get(о.id, ()))
        for ід in потрібні:
            self.ребро(self.а.об_за_id[ід], звідки, куди, місце)

    def підготувати(self):
        """Один раз індексує вміст для всіх кандидатів, без обходу купи на кожний виклик."""
        а = self.а
        а.об_за_id = {о.id: о for о in а.об.values()}
        потрібні = {о.id for о, ключ, вал, _, _ in а.записи.values()
                    if о.рек and (а.код_ключ(ключ) or any(not hasattr(в, "пол") and в[0] in ("D", "TP") for в in вал))}
        for місце in set(а.читання3) | {м for читання in self.переліки.values() for м in читання}:
            потрібні.update(ід for ід, _ in self.читання.get(місце, ()))
        потрібні.update(о.id for читачі in self.сирі_читачі.values() for о, _, _ in читачі)
        батьки = {}
        for о in а.об.values():
            for ключ, вал in о.пол.items():
                if ключ != "#ключі":
                    for в in вал:
                        if hasattr(в, "пол"):
                            батьки.setdefault(в.id, set()).add(о.id)
        self.нащадки = {ід: {ід} for ід in потрібні}
        черга = deque(sorted(потрібні))
        у_черзі = set(потрібні)
        while черга:
            ід = черга.popleft()
            у_черзі.discard(ід)
            for батько in батьки.get(ід, ()):
                ціль = self.нащадки.setdefault(батько, set())
                нові = self.нащадки[ід] - ціль
                if нові:
                    ціль.update(нові)
                    if батько not in у_черзі:
                        черга.append(батько)
                        у_черзі.add(батько)

    def вміст(self, вал):
        """Обходить тільки ребра збережених полів, без сусідніх змінних."""
        черга = deque((о, ()) for о in вал if hasattr(о, "пол"))
        бачені = set()
        while черга:
            о, шлях = черга.popleft()
            if о.id in бачені:
                continue
            бачені.add(о.id)
            yield о, шлях
            for ключ, значення in sorted(о.пол.items(), key=lambda п: str(п[0])):
                if ключ == "#ключі":
                    continue
                for в in sorted((в for в in значення if hasattr(в, "пол")), key=lambda в: в.id):
                    черга.append((в, шлях + ((о.файл, о.рядок),)))

    def файл(self, вал, сирі=False):
        """Впізнає файл формату, не довільний JSON чи звіт з назвою каталог."""
        шляхи = sorted({в[1] for в in вал if not hasattr(в, "пол") and в[0] in ("L", "U", "F")
                        and isinstance(в[1], str) and (ФАЙЛ_КАТАЛОГУ.search(в[1])
                        or (сирі and ФАЙЛ_ЖНИВ.search(в[1])))})
        return шляхи[0] if шляхи else None

    def якір(self, вал, ф, рядок, файл, напрям, маршрут=()):
        """Пов'язує лише вміст конкретного слота формату з файловою межею."""
        for ключ in маршрут:
            вал = {в for о in вал if hasattr(о, "пол") for в in о.пол.get(ключ, ())}
        for о, вкладення in self.вміст(вал):
            if о.вид not in ("dict", "rec"):
                continue
            if напрям == "читання" and self.області.get(о.id) != ф.fid:
                continue
            дж = sorted(self.літерали.get(файл, ()))
            початок = ((ф.file, рядок),)
            if дж:
                початок += (next((м for м in дж if м[0] == ф.file), дж[0]),)
            доказ = (ф.fid, початок, вкладення, файл, напрям)
            self.якорі.setdefault(о.id, set()).add(доказ)
            if not о.рек:
                о.рек = True
                self.а.змін += 1

    def читач_формату(self, ф):
        """Прив'язує слоти повернення читачів XML до їхнього файлового аргументу."""
        формати = {("фід_розбір", "читати_yml_кроками"): (("0", "*"), "open"),
                   ("фід_каталог", "прочитати_каталог"): (("каталог", "*"), "читати_yml")}
        договір = формати.get((ф.mod, ф.name))
        if not договір or not ф.params:
            return
        файл = self.файл(self.а.env.get((ф.fid, ф.params[0]), ()))
        читання = [в.line for оп in ф.stmts for в in вирази(оп.val)
                   if в.k == "call" and в.a[0].k in ("name", "attr") and в.a[0].v == договір[1]]
        if файл and читання:
            self.якір(self.а.ret.get(ф.fid, ()), ф, min(читання), файл, "читання", договір[0])

    def шлях(self, о, область):
        """Будує свідок лише по ребрах передачі цього об'єкта."""
        ключ = (о.id, область)
        if ключ in self.докази:
            return self.докази[ключ]
        початкова = self.області.get(о.id)
        граф = self.переходи.get(о.id, {})

        def між(звідки, куди):
            черга = deque([(звідки, ())])
            бачені = {звідки}
            while черга:
                вузол, ланки = черга.popleft()
                if вузол == куди:
                    return ланки
                for ціль, місце in sorted(граф.get(вузол, ())):
                    if ціль not in бачені:
                        бачені.add(ціль)
                        черга.append((ціль, ланки + (місце,)))
            return None

        for якір, ланки, вкладення, файл, напрям in sorted(self.якорі.get(о.id, ())):
            залежність = self.залежності.get((о.id, (якір, ланки, вкладення, файл, напрям)))
            if залежність:
                запис, область_читача = залежність
                далі = self.шлях(запис, область_читача)
                if not далі:
                    continue
                ланки += tuple((ф, int(р)) for ф, _, р in (л.rpartition(":") for л in далі["ланки"]))
            передача = між(область, якір) if напрям == "запис" else між(якір, область)
            if передача is None:
                continue
            створення = (о.файл, о.рядок)
            if напрям == "запис":
                шлях = передача + вкладення + ланки
            else:
                шлях = tuple(reversed(ланки)) + вкладення + (створення,) + передача
            # Порядок ланок істотний; повтори сусідніх місць — ні.
            чистий = []
            for ф, р in шлях:
                if р and (not чистий or чистий[-1] != (ф, р)):
                    чистий.append((ф, р))
            відповідь = {"файл_каталогу": файл, "напрям": напрям,
                         "створено": f"{о.файл}:{о.рядок}",
                         "ланки": [f"{ф}:{р}" for ф, р in чистий]}
            self.докази[ключ] = відповідь
            return відповідь
        return None

    def зєднати_жнива(self):
        """З'єднує дві сторони JSON жниварки за слотами його файлового формату."""
        for слот, читачі in self.сирі_читачі.items():
            for запис, ф, рядок in читачі:
                for доказ in tuple(self.якорі.get(запис.id, ())):
                    if not ФАЙЛ_КАТАЛОГУ.search(доказ[3]):
                        continue
                    for о, писач, рядок_запису in self.сирі_писачі.get(слот, ()):
                        новий = (писач.fid, ((писач.file, рядок_запису), (ф.file, рядок)), (), доказ[3], "запис")
                        self.якорі.setdefault(о.id, set()).add(новий)
                        self.залежності[(о.id, новий)] = (запис, ф.fid)
                        if not о.рек:
                            о.рек = True
                            self.а.змін += 1

    def очистити(self):
        """Скидає кеш шляхів перед знімком остаточного графа."""
        self.докази.clear()
