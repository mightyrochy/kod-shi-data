def git(*аргументи, вхід=None, перевірити=True):
    """Один виклик git з `core.quotepath=false` (кириличні шляхи — як є)."""
    готово = subprocess.run(["git", "-c", "core.quotepath=false", *аргументи], input=вхід, capture_output=True,
                            check=False)
    if перевірити and готово.returncode != 0:
        raise RuntimeError("git " + " ".join(аргументи) + ": " + готово.stderr.decode("utf-8", "replace").strip())
    return готово


def _текст(байти):
    return байти.decode("utf-8", "replace")


def _час(iso):
    return datetime.fromisoformat(iso.replace("Z", "+00:00")).astimezone(timezone.utc)


def злиття_вікна(main, від, до):
    """Злиті PR — коміти першого батька `main` з датою коміту ≥ `від`. Сквош: тема `… (#N)`, повідомлення — його
    тіло, автор — автор PR. Коміт злиття (`Merge pull request #N from <власник>/<гілка>` чи своя назва `… (#N)`, два
    батьки): повідомлення — коміти гілки (`батько1..батько2`), довіра — власник гілки чи автор. Інші коміти (збірка,
    згортання дошки) — не PR. Усі коміти — і для злиттів за часом (`злиття_за_часом`)."""
    вивід = _текст(git("log", "--first-parent", "--since=" + від.isoformat(), "--until=" + до.isoformat(),
                       "--format=%H%x1f%cI%x1f%an%x1f%P%x1f%s%x1f%B%x1e", main).stdout)
    злиття, усі = [], []
    for запис in вивід.split("\x1e"):
        запис = запис.lstrip("\n")
        if not запис:
            continue
        sha, час, автор, батьки, тема, тіло = запис.split("\x1f", 5)
        батьки = батьки.split()
        усі.append((_час(час), sha))
        гілка, номер = ЗЛИТТЯ_PR.match(тема), ТЕМА_PR.search(тема)
        if гілка:
            pr, автор = int(гілка.group(1)), гілка.group(2)
        elif номер:
            pr = int(номер.group(1))
        else:
            continue
        if len(батьки) == 2:
            тіло = _текст(git("log", "--format=%B%x1e", батьки[0] + ".." + батьки[1]).stdout)
        злиття.append({"sha": sha, "час": _час(час), "автор": автор, "pr": pr, "тіло": тіло})
    return злиття, усі


def злиття_за_часом(усі, коли):
    """PR, влитий іншим PR (пачка), свого коміту злиття не має: його злиття — останній коміт першого батька `main`
    з часом не пізніше за `merged_at` (GitHub ставить його тієї ж секунди чи трохи пізніше за коміт)."""
    придатні = [(час, sha) for час, sha in усі if час <= коли]
    return max(придатні)[1] if придатні else ""


def прочитати_тіла(шляхи):
    """Тіла PR з файлів: потік JSON-значень — відповідь пошуку (`items`, `total_count`), список PR чи один PR.
    Повертає {номер: {"тіло", "логін"}} і попередження (неповна відповідь пошуку)."""
    тіла, попередження = {}, []
    декодер = json.JSONDecoder()
    for шлях in шляхи:
        with open(шлях, encoding="utf-8") as ф:
            текст = ф.read()
        позиція, пунктів, заявлено = 0, 0, 0
        while True:
            while позиція < len(текст) and текст[позиція].isspace():
                позиція += 1
            if позиція >= len(текст):
                break
            значення, позиція = декодер.raw_decode(текст, позиція)
            if isinstance(значення, dict) and "items" in значення:
                заявлено = max(заявлено, int(значення.get("total_count") or 0))
                значення = значення["items"]
            for pr in значення if isinstance(значення, list) else [значення]:
                if not isinstance(pr, dict) or not isinstance(pr.get("number"), int):
                    continue
                пунктів += 1
                злито = pr.get("merged_at") or (pr.get("pull_request") or {}).get("merged_at")
                тіла[pr["number"]] = {"тіло": pr.get("body") or "", "логін": (pr.get("user") or {}).get("login", ""),
                                      "злито": _час(злито) if злито else None}
        if заявлено > пунктів:
            попередження.append(f"{шлях}: пошук знайшов {заявлено}, у файлі {пунктів} — дочитай сторінки")
    return тіла, попередження


def команда_тіл(від):
    """Один пошук GitHub дає тіла всіх злитих PR вікна з «ЖИВИЙ ПІСЛЯ» (по 100 на сторінку)."""
    запит = (f"repo:mightyrochy/kod-shi-data is:pr is:merged merged:>={від.strftime('%Y-%m-%dT%H:%M:%SZ')} "
             f"\"ЖИВИЙ ПІСЛЯ\" in:body")
    return (f"for p in 1 2 3; do gh api -X GET search/issues -f q='{запит}' -f per_page=100 -f page=$p; done "
            f"> /tmp/тіла.json")


def найстаріший_доступний(main):
    """Час найстарішого коміту історії `main`, яку має клон (неглибокий клон обриває її)."""
    вивід = _текст(git("log", "--first-parent", "--format=%cI", main).stdout).split()
    return _час(вивід[-1]) if вивід else None


def прочитати_файли(main, шляхи):
    """Вміст файлів дерева `main` одним `git cat-file --batch`."""
    if not шляхи:
        return {}
    запит = "".join(main + ":" + шлях + "\n" for шлях in шляхи).encode("utf-8")
    вивід = git("cat-file", "--batch", вхід=запит).stdout
    файли, позиція = {}, 0
    for шлях in шляхи:
        кінець = вивід.index(b"\n", позиція)
        шапка = вивід[позиція:кінець].split()
        позиція = кінець + 1
        if len(шапка) < 3 or шапка[1] != b"blob":
            continue
        розмір = int(шапка[2])
        файли[шлях] = _текст(вивід[позиція:позиція + розмір])
        позиція += розмір + 1
    return файли


def предки(sha, кеш):
    """Множина комітів, досяжних зі збірки `sha` (у межах історії клону); None — збірки в клоні нема."""
    if sha not in кеш:
        готово = git("rev-list", sha, "--", перевірити=False)
        кеш[sha] = set(_текст(готово.stdout).split()) if готово.returncode == 0 else None
    return кеш[sha]


def _згадує(текст, ід):
    return re.search(r"(?<![\w-])" + re.escape(ід) + r"(?![\w-])", текст) is not None


def звіти(main, змінені_у_вікні):
    """Усі `ЗВІТ.md` під `аудит/` голови `main`: межа збірки (чи вадна), текст і теки поруч."""
    шляхи = [ш for ш in _текст(git("ls-tree", "-r", "--name-only", main, "--", "аудит").stdout).splitlines()]
    звітні = [ш for ш in шляхи if ш.rsplit("/", 1)[-1] == "ЗВІТ.md"]
    тексти = прочитати_файли(main, звітні)
    теки_звітів = {ш.rpartition("/")[0] for ш in звітні}
    теки_поруч = {}
    for ш in шляхи:
        частини = ш.split("/")
        for к in range(1, len(частини)):
            батько = "/".join(частини[:к])
            if батько in теки_звітів:
                теки_поруч.setdefault(батько, set()).add(частини[к])
    результат = []
    for шлях in звітні:
        текст = тексти.get(шлях, "")
        межі = МЕЖА_ЗБІРКИ.findall(текст)
        тека = шлях.rpartition("/")[0]
        результат.append({
            "шлях": шлях, "текст": текст, "сусіди": теки_поруч.get(тека, set()),
            "збірка": межі[0] if len(межі) == 1 else "",
            "кілька_меж": len(межі) > 1,
            "межа_не_за_форматом": not межі and ЧУЖА_МЕЖА.search(текст) is not None,
            "у_вікні": шлях in змінені_у_вікні,
        })
    return результат


def змінені_файли(main, від):
    """Файли, змінені комітами першого батька `main` від `від`, з часом першої зміни у вікні."""
    вивід = _текст(git("log", "--first-parent", "--since=" + від.isoformat(), "--name-only", "--format=\x1e%cI",
                       main).stdout)
    файли = {}
    for запис in вивід.split("\x1e"):
        рядки = [р for р in запис.split("\n") if р]
        if not рядки:
            continue
        час = _час(рядки[0])
        for шлях in рядки[1:]:
            if шлях not in файли or час < файли[шлях]:
                файли[шлях] = час
    return файли


# --- прогнано за записами: дослівний повтор Get-AutoRanPairs (queue_lanes.ps1) ------------------------------------
def _рядок(значення):
    return "" if значення is None else str(значення)


def _властивість(об, ім_я):
    """Get-JsonProp: властивість об'єкта JSON чи None (не об'єкт — None)."""
    return об.get(ім_я) if isinstance(об, dict) else None


def _json(текст):
    return json.loads(текст.lstrip("\ufeff"))


def прогнані_записами(main, теки=None):
    """Get-AutoRanPairs: пара (PR, сцена) прогнана, коли вона є в `ПЛАН.json` теки звіту (`scenes`), журнал `done.txt`
    не має відмови сцени чи питання, а запис сцени завершено: `результат.json` з rc 0 чи 1 і SHA живого коду,
    `повтор.json`, `лог.txt`, `знімки/доказ.json`, `VIDPOVIDI/обмін`. Запис — у теці звіту чи перенесений
    `нова_база.js` в `аудит/проби/нічні/` (`походження.json`). Теки — звітів автоживого й Е1 (`ТЕКА_ЗВІТУ`) і хмарних
    прогонів (`ТЕКА_ХМАРИ`). Дерево — `main` (у обгортці — голова звіту; хмарні — дерево збірки плану).
    Повертає {"PR|сцена": [{"sha": SHA коду запису, "звіт": тека, "питання": текст із `ПЛАН.json`}]}; що злиття PR —
    предок SHA, перевіряє лічба, а чи не дала оцінка теки «не виміряно» — `без_відповіді_оцінок`."""
    шляхи = [ш.rstrip("\r") for ш in _текст(git("ls-tree", "-r", "--name-only", main, "--", "аудит/проби").stdout)
             .split("\n") if ш.rstrip("\r")]
    множина = set(шляхи)
    перенесені = {}
    for ш in шляхи:
        збіг = re.match(r"^(аудит/проби/нічні/[^/]+/([^/]+))/походження\.json$", ш)
        if збіг:
            перенесені.setdefault(збіг.group(2), []).append(збіг.group(1))
    обмін = {ш[:ш.index("/VIDPOVIDI/обмін/")] for ш in шляхи if ш.find("/VIDPOVIDI/обмін/") > 0}
    знайдені = sorted({ш[len(КОРІНЬ_ПРОБ):].split("/")[0] for ш in шляхи if ш.startswith(КОРІНЬ_ПРОБ) and "/" in ш[len(КОРІНЬ_ПРОБ):]})
    теки = [т for т in (теки if теки is not None else знайдені) if ТЕКА_ЗВІТУ.match(т) or ТЕКА_ХМАРИ.match(т)]
    результат = {}
    for тека in теки:
        каталог = КОРІНЬ_ПРОБ + тека
        файли = прочитати_файли(main, [каталог + "/ПЛАН.json", каталог + "/done.txt"])
        if len(файли) < 2:
            continue
        try:
            план = _json(файли[каталог + "/ПЛАН.json"])
            відмови = set()
            for рядок in файли[каталог + "/done.txt"].split("\n"):
                if not рядок.strip():
                    continue
                запис = _json(рядок)
                сцена = _рядок(_властивість(запис, "сцена"))
                if _властивість(запис, "відмова_питання") is not None:
                    відмови.add(_рядок(_властивість(запис, "pr")) + "|" + сцена)
                elif _властивість(запис, "відмова") is not None:
                    відмови.add("*|" + сцена)
        except ValueError:
            continue
        сцени = _властивість(план, "scenes")
        if not isinstance(сцени, dict):
            continue
        for сцена, питання in сцени.items():
            записи = [каталог + "/" + сцена]
            for база in перенесені.get(сцена, []):
                походження = прочитати_файли(main, [база + "/походження.json"])
                try:
                    звідки = _рядок(_властивість(_json(походження[база + "/походження.json"]), "шлях_запису")).replace("\\", "/")
                except (KeyError, ValueError):
                    continue
                if звідки == каталог + "/" + сцена:
                    записи.append(база)
            код = ""
            for запис in записи:
                if запис not in обмін or any(запис + "/" + ф not in множина for ф in ФАЙЛИ_ЗАПИСУ):
                    continue
                try:
                    рез = _json(прочитати_файли(main, [запис + "/результат.json"])[запис + "/результат.json"])
                except (KeyError, ValueError):
                    continue
                rc, sha = _властивість(рез, "rc"), _рядок(_властивість(рез, "sha"))
                if isinstance(rc, int) and not isinstance(rc, bool) and 0 <= rc <= 1 and re.fullmatch(r"[0-9a-f]{40}", sha):
                    код = sha
                    break
            if not код or "*|" + сцена in відмови:
                continue
            for п in питання if isinstance(питання, list) else [питання]:
                ключ = _рядок(_властивість(п, "pr")) + "|" + сцена
                if ключ in відмови:
                    continue
                результат.setdefault(ключ, []).append({"sha": код, "звіт": тека,
                                                      "питання": _рядок(_властивість(п, "question"))})
    return результат


ОЦІНКА_ФАЙЛ = re.compile(r"^аудит/(?:перевірки|проби)/[Оо]цінка[^/]*\.md$")
ТЕКА_В_ОЦІНЦІ = re.compile(r"(?<![\w-])(автоживий-[0-9a-f]{40}|Е1-нічний-живий-[0-9]{8}|Тестовий-прогін-хмара-[\w-]+)(?![\w-])")
_РОЗДІЛЬНИК = re.compile(r"^\|(?:" + _S + r"*:?-+:?" + _S + r"*\|)+$")
_НОМЕР_PR = re.compile(r"(?<![0-9A-Za-z])#?([0-9]{3,6})(?![0-9A-Za-z])")


def _клітина(текст):
    return _обрізати(текст.replace("*", "").replace("`", ""))


def без_відповіді_оцінок(main):
    """Get-AutoEvalUnanswered: рядки «не виміряно» таблиць оцінок (`аудит/перевірки/`, `аудит/проби/`, файл
    `Оцінка…md`/`оцінка…md`) — {"тека|PR|сцена": {"де": "файл:рядок", "причина": …, "обрив": вердикт «не виміряно
    (обрив)» — питання йде в план, а не в `bad`}}; тека — кожна тека прогону, яку
    називає файл; пара, яку хоч одна оцінка дала з іншим вердиктом, — з відповіддю й не повертається."""
    шляхи = sorted(ш.rstrip("\r") for ш in _текст(git("ls-tree", "--name-only", main, "--", "аудит/перевірки/",
                                                      "аудит/проби/").stdout).split("\n")
                   if ОЦІНКА_ФАЙЛ.match(ш.rstrip("\r")))
    тексти = прочитати_файли(main, шляхи)
    відповіли, знайдені = set(), {}
    for шлях in шляхи:
        if шлях not in тексти:
            continue
        текст = тексти[шлях]
        теки = []
        for збіг in ТЕКА_В_ОЦІНЦІ.finditer(текст):
            if збіг.group(1) not in теки:
                теки.append(збіг.group(1))
        if not теки:
            continue
        рядки = текст.split("\n")
        і = 0
        while і < len(рядки):
            рядок = _обрізати(рядки[і])
            if not рядок.startswith("|") or і + 1 >= len(рядки) or not _РОЗДІЛЬНИК.match(_обрізати(рядки[і + 1])):
                і += 1
                continue
            назви = [_клітина(к) for к in рядок.strip("|").split("|")]
            сцена_к = next((к for к, н in enumerate(назви) if н == "сцена"), -1)
            pr_к = next((к for к, н in enumerate(назви) if re.match(r"^PR(?:" + _S + r"|$)", н)), -1)
            вердикт_к = next((к for к, н in enumerate(назви) if н in ("відповідь", "вердикт")), -1)
            і += 2
            while і < len(рядки) and _обрізати(рядки[і]).startswith("|"):
                номер = і
                і += 1
                if сцена_к < 0 or pr_к < 0 or вердикт_к < 0:
                    continue
                клітини = _обрізати(рядки[номер]).strip("|").split("|")
                if len(клітини) > len(назви):
                    клітини = клітини[:len(назви) - 1] + ["|".join(клітини[len(назви) - 1:])]
                if len(клітини) != len(назви):
                    continue
                клітини = [_клітина(к) for к in клітини]
                сцена = re.match(r"^[^" + re.escape(_ПРОБІЛИ_NET) + r"(]+", клітини[сцена_к])
                if not сцена:
                    continue
                номери = []
                for збіг in _НОМЕР_PR.finditer(клітини[pr_к]):
                    if збіг.group(1) not in номери:
                        номери.append(збіг.group(1))
                вердикт = клітини[вердикт_к]
                відкрите = re.match("^не виміряно", вердикт, re.IGNORECASE) is not None
                обрив = вердикт.startswith("не виміряно (обрив)")
                причина = ""
                if відкрите:
                    причина = _обрізати(re.sub(r"^не виміряно(?: \(обрив\))?[" + re.escape(_ПРОБІЛИ_NET) + r":.,;—–-]*", "",
                                               вердикт, flags=re.IGNORECASE))
                    if not причина and вердикт_к != len(назви) - 1:
                        причина = клітини[-1]
                for тека in теки:
                    for pr in номери:
                        ключ = f"{тека}|{pr}|{сцена.group(0)}"
                        if not відкрите:
                            відповіли.add(ключ)
                        elif ключ not in знайдені:
                            знайдені[ключ] = {"де": f"{шлях}:{номер + 1}", "причина": причина, "обрив": обрив}
    return {к: в for к, в in знайдені.items() if к not in відповіли}


def є_предком(злиття, код, кеш):
    """Коміт злиття PR — предок (чи рівний) SHA запису: запис прогнав код із цим злиттям."""
    ключ = (злиття, код)
    if ключ not in кеш:
        кеш[ключ] = git("merge-base", "--is-ancestor", злиття, код, перевірити=False).returncode == 0
    return кеш[ключ]


# --- лічба ----------------------------------------------------------------------------------------------------------
def лічити(main, від, зараз, тіла=None):
    """Питання (PR × сцена) вікна, прогнані й ні; вадні рядки; що не виміряно. `тіла` — {номер: {"тіло", "логін"}}
    з файлу (джерело плану обгортки); None — рядки з повідомлень злиття."""
    текст_реєстру = прочитати_файли(main, [РЕЄСТР_ШЛЯХ]).get(РЕЄСТР_ШЛЯХ, "")
    реєстр = реєстр_сцен(текст_реєстру)
    входи = входи_сцен(текст_реєстру, реєстр)
    if not реєстр:
        raise RuntimeError("реєстр " + РЕЄСТР_ШЛЯХ + " порожній на " + main)
    злиття, усі_коміти = злиття_вікна(main, від, зараз)
    за_часом = []
    if тіла is not None:
        злиті = {коміт["pr"] for коміт in злиття}
        for номер, т in sorted(тіла.items()):
            if номер in злиті or т["злито"] is None or not (від <= т["злито"] <= зараз):
                continue
            sha = злиття_за_часом(усі_коміти, т["злито"])
            if sha:
                за_часом.append(номер)
                злиття.append({"sha": sha, "час": т["злито"], "автор": т["логін"], "pr": номер, "тіло": ""})
    змінені = змінені_файли(main, від)
    усі_звіти = звіти(main, змінені)
    кеш = {}
    з_межею = []
    for звіт in усі_звіти:
        # Рядок `ПЕРЕВІРЕНО ЗБІРКУ` — межа лише у звітах, які читає й обгортка (теки автоживого й Е1).
        if звіт["збірка"] and ТЕКА_ЗВІТУ.match(звіт["шлях"].split("/")[2] if звіт["шлях"].startswith(КОРІНЬ_ПРОБ) else ""):
            звіт["предки"] = предки(звіт["збірка"], кеш)
            з_межею.append(звіт)
    питання, вадні, чужі, лише_в_повідомленні = {}, [], [], []
    pr_злитих = рядків = 0
    pr_з_рядком = set()
    for коміт in злиття:
        pr = коміт["pr"]
        pr_злитих += 1
        if тіла is None:
            пункти = рядки_живий_після(коміт["тіло"], реєстр)
        else:
            пункти = рядки_живий_після(тіла[pr]["тіло"], реєстр) if pr in тіла else []
            if pr not in тіла and коміт["автор"] == ДОВІРЕНИЙ_АВТОР and any(
                    not п["error"] for п in рядки_живий_після(коміт["тіло"], реєстр)):
                лише_в_повідомленні.append(pr)
            if pr in тіла and тіла[pr]["логін"] != ДОВІРЕНИЙ_АВТОР and пункти:
                чужі.append((pr, тіла[pr]["логін"]))
                continue
        if not пункти:
            continue
        if коміт["автор"] != ДОВІРЕНИЙ_АВТОР:
            чужі.append((pr, коміт["автор"]))
            continue
        pr_з_рядком.add(pr)
        for пункт in пункти:
            рядків += 1
            if пункт["error"]:
                if any(в["pr"] == pr and в["рядок"] == пункт["line"] for в in вадні):
                    continue
                вадні.append({"pr": pr, "рядок": пункт["line"], "вада": пункт["error"],
                              "не_потрібен": bool(НЕ_ПОТРІБЕН.search(пункт["line"]))})
                continue
            ключ = (pr, пункт["id"])
            if ключ not in питання:
                питання[ключ] = {"pr": pr, "сцена": пункт["id"], "режим": пункт["mode"], "злиття": коміт["sha"],
                                 "час": коміт["час"], "звіти": [], "записи": [], "тексти": [], "без_відповіді": []}
            питання[ключ]["тексти"].append(пункт["question"])
    за_записами = прогнані_записами(main)
    оцінки = без_відповіді_оцінок(main)
    кеш_предків = {}
    for п in питання.values():
        # Запис сцени (як `Get-AutoRanPairs`): сцена «функція» — хмарна, її обгортка не ганяє.
        if not п["режим"].startswith("функція"):
            for запис in за_записами.get(f"{п['pr']}|{п['сцена']}", []):
                if not є_предком(п["злиття"], запис["sha"], кеш_предків):
                    continue
                # Запис, який оцінка його теки дала «не виміряно», відповіді не дав (Get-AutoEvalUnanswered).
                оцінка = оцінки.get(f"{запис['звіт']}|{п['pr']}|{п['сцена']}")
                if оцінка:
                    п["без_відповіді"].append(dict(оцінка, тека=запис["звіт"], питання=запис["питання"]))
                elif запис["звіт"] not in п["записи"]:
                    п["записи"].append(запис["звіт"])
        for звіт in з_межею:
            if звіт["предки"] and п["злиття"] in звіт["предки"] and (
                    _згадує(звіт["текст"], п["сцена"]) or п["сцена"] in звіт["сусіди"]):
                # Звіт, чию пару оцінка його теки дала «не виміряно», теж відповіді не дав: межа збірки прогнаним не
                # робить того, що записи вже не зарахували.
                тека = звіт["шлях"].split("/")[2]
                оцінка = оцінки.get(f"{тека}|{п['pr']}|{п['сцена']}")
                if not оцінка:
                    п["звіти"].append(звіт["шлях"])
                elif not any(б["тека"] == тека for б in п["без_відповіді"]):
                    п["без_відповіді"].append(dict(оцінка, тека=тека, питання=None))
    непрогнані = sorted((п for п in питання.values() if not п["звіти"] and not п["записи"]), key=lambda п: (п["час"], п["pr"], п["сцена"]))
    for п in непрогнані:
        # Як план (Get-AutoLivePlan): питання, на яке сцена не відповість, і той самий текст, що оцінка дала «не
        # виміряно», — у `bad` з причиною; змінений рядок — знову в плані.
        хмара = п["режим"].startswith("функція")
        п["відсіяно"] = []
        for текст in п["тексти"]:
            причина = "" if хмара else непридатне_питання(текст, п["режим"], входи.get(п["сцена"], ""))
            оцінка = next((б for б in п["без_відповіді"] if б["питання"] == текст), None)
            if причина:
                п["відсіяно"].append("не для живого прогону: " + причина)
            elif оцінка and not оцінка["обрив"]:
                п["відсіяно"].append(f"не виміряно в оцінці {оцінка['де']}: {оцінка['причина']}")
    без_межі = []
    for звіт in усі_звіти:
        if звіт["збірка"] or not звіт["у_вікні"]:
            continue
        час_звіту = змінені[звіт["шлях"]]
        згадано = [п for п in непрогнані if п["час"] < час_звіту and (
            _згадує(звіт["текст"], п["сцена"]) or п["сцена"] in звіт["сусіди"])]
        if згадано:
            без_межі.append({"шлях": звіт["шлях"], "час": час_звіту, "згадано": len(згадано)})
    злиті_номери = {коміт["pr"] for коміт in злиття}
    return {
        "з_тіл": тіла is not None, "лише_в_повідомленні": sorted(лише_в_повідомленні), "за_часом": за_часом,
        "тіла_поза_main": sorted(н for н, т in (тіла or {}).items() if н not in злиті_номери
                                 and (т["злито"] is None or від <= т["злито"] <= зараз)),
        "pr_злитих": pr_злитих, "pr_з_рядком": len(pr_з_рядком), "рядків": рядків, "питання": питання,
        "непрогнані": непрогнані, "вадні": вадні, "чужі": чужі, "без_межі": без_межі,
        "не_за_форматом": [з["шлях"] for з in усі_звіти
                           if з["у_вікні"] and (з["межа_не_за_форматом"] or з["кілька_меж"])],
        "збірки_нема": [з["шлях"] for з in з_межею if з["предки"] is None],
        "без_відповіді": [п for п in непрогнані if п["без_відповіді"]],
        "відсіяно": [п for п in непрогнані if п["відсіяно"]],
        "звітів_з_межею": len(з_межею), "звіти_записів": len({з for п in питання.values() for з in п["записи"]}),
        "за_записами": sum(1 for п in питання.values() if п["записи"]),
        "лише_за_рядком": sum(1 for п in питання.values() if п["звіти"] and not п["записи"]),
    }


def _utc(час):
    return час.strftime("%Y-%m-%d %H:%MZ")


def надрукувати(main_sha, від, зараз, лічба, попередження=(), пари=False):
    м = len(лічба["питання"])
    н = м - len(лічба["непрогнані"])
    print(f"Вікно: {_utc(від)} — {_utc(зараз)}; main {main_sha}")
    print("Джерело рядків: " + ("тіла PR із файлу (як у плані обгортки)" if лічба["з_тіл"] else
                                "повідомлення злиття — тіл PR не дано, M — нижня межа"))
    print(f"Злитих PR у вікні: {лічба['pr_злитих']}, з рядком ЖИВИЙ ПІСЛЯ: {лічба['pr_з_рядком']}; рядків у "
          f"{'тілах PR' if лічба['з_тіл'] else 'повідомленнях злиття'}: {лічба['рядків']}, вадних різних: {len(лічба['вадні'])} "
          f"(з них «не потрібен»: {sum(1 for в in лічба['вадні'] if в['не_потрібен'])})")
    print(f"Питань (PR × сцена): {м}; прогнано: {н}; звітів з ПЕРЕВІРЕНО ЗБІРКУ у main: {лічба['звітів_з_межею']}")
    print(f"Прогнано за записами (як Get-AutoRanPairs): {лічба['за_записами']} (звітів: {лічба['звіти_записів']}); "
          f"лише за рядком ПЕРЕВІРЕНО ЗБІРКУ: {лічба['лише_за_рядком']}")
    if пари:
        print("Прогнані за записами (PR|сцена → звіти):")
        for п in sorted(лічба["питання"].values(), key=lambda п: (п["pr"], п["сцена"])):
            if п["записи"]:
                print(f"  {п['pr']}|{п['сцена']}\t" + ", ".join(п["записи"]))
    if лічба["непрогнані"]:
        print("Непрогнані (PR, злито UTC, сцена, режим, годин від злиття):")
        for п in лічба["непрогнані"]:
            годин = (зараз - п["час"]).total_seconds() / 3600
            print(f"  #{п['pr']}\t{_utc(п['час'])}\t{п['сцена']}\t{п['режим']}\t{годин:.1f}")
    if лічба["без_відповіді"]:
        print("Без відповіді — запис чи звіт з межею збірки є, а оцінка його теки дала «не виміряно» (PR|сцена, оцінка, далі в плані):")
        for п in лічба["без_відповіді"]:
            той_самий = any(б["питання"] in п["тексти"] and not б["обрив"] for б in п["без_відповіді"])
            print(f"  #{п['pr']}|{п['сцена']}\t{п['без_відповіді'][0]['де']}\t"
                  + ("той самий текст — у bad, доки рядок ЖИВИЙ ПІСЛЯ не виправлено" if той_самий else
                     "рядок змінено чи обрив — знову в плані"))
    if лічба["відсіяно"]:
        print(f"План відсіє до прогону (bad з причиною, сцени заради них не пише): {len(лічба['відсіяно'])} питань")
        for п in лічба["відсіяно"]:
            print(f"  #{п['pr']}|{п['сцена']}\t{п['відсіяно'][0][:160]}")
    if лічба["вадні"]:
        print("Вадні рядки (не питання: план їх не прожене):")
        for в in лічба["вадні"]:
            print(f"  #{в['pr']}\t{в['вада']}\t{в['рядок'][:120]}")
    print("Не виміряно:")
    if not лічба["з_тіл"]:
        print("  тіла PR — не в git; дай --тіла <файл>, файл — одна команда: " + команда_тіл(від))
    for рядок in попередження:
        print("  " + рядок)
    for pr in лічба["лише_в_повідомленні"]:
        print(f"  #{pr}: рядок ЖИВИЙ ПІСЛЯ є в повідомленні злиття, а у файлі тіл PR нема — не рахується")
    if лічба["за_часом"]:
        print(f"  свого коміту злиття в main нема (влито іншим PR) — злиття взято за часом merged_at: "
              f"{len(лічба['за_часом'])} PR: " + ", ".join("#" + str(н) for н in лічба["за_часом"][:30]))
    if лічба["тіла_поза_main"]:
        print("  PR із файлу тіл, яких нема серед злиттів вікна в історії main (вікно, неглибока історія чи старий "
              "main): " + ", ".join("#" + str(н) for н in лічба["тіла_поза_main"][:30]))
    for з in лічба["без_межі"]:
        print(f"  звіт без ПЕРЕВІРЕНО ЗБІРКУ (не рахується прогнаним): {з['шлях']} ({_utc(з['час'])}), згадує сцен "
              f"непрогнаних питань, злитих раніше за нього: {з['згадано']}")
    for шлях in лічба["не_за_форматом"]:
        print(f"  ПЕРЕВІРЕНО ЗБІРКУ не за форматом «ПЕРЕВІРЕНО ЗБІРКУ: <SHA>» окремим рядком (не рахується): {шлях}")
    for шлях in лічба["збірки_нема"]:
        print(f"  збірки звіту нема в історії клону: {шлях}")
    for pr, автор in лічба["чужі"]:
        print(f"  #{pr}: автор {автор}, не {ДОВІРЕНИЙ_АВТОР} — пропущено, як у плані обгортки")
    к = len(лічба["без_відповіді"])
    print(f"прогнано: {н} · без відповіді: {к} · решта: {м - н - к} (з {м})")
    print(f"прогнано: {н} з {м}" + ("" if лічба["з_тіл"] else " (без тіл PR: M — нижня межа)"))


def main(аргументи=None):
    розбір = argparse.ArgumentParser(description="Питання ЖИВИЙ ПІСЛЯ злитого: прогнано N з M (лише git).")
    розбір.add_argument("--діб", type=float, default=7.0, help="вікно злиття в добах до --зараз (типово 7)")
    розбір.add_argument("--від", help="початок вікна ISO (UTC), замість --діб")
    розбір.add_argument("--зараз", help="кінець вікна й відлік годин ISO (UTC); типово — годинник машини")
    розбір.add_argument("--пари", action="store_true", help="надрукувати прогнані за записами пари PR|сцена")
    розбір.add_argument("--main", default="", help="гілка чи коміт main (типово origin/main, нема — main)")
    розбір.add_argument("--тіла", action="append", default=[], help="файл тіл PR (відповідь пошуку GitHub); можна кілька")
    а = розбір.parse_args(аргументи)
    os.chdir(_текст(git("rev-parse", "--show-toplevel").stdout).strip())
    main_ref = а.main or next(
        (р for р in ("origin/main", "main") if git("rev-parse", "--verify", "-q", р, перевірити=False).returncode == 0),
        "HEAD")
    main_sha = _текст(git("rev-parse", main_ref).stdout).strip()
    зараз = _час(а.зараз) if а.зараз else datetime.now(timezone.utc)
    від = _час(а.від) if а.від else зараз - timedelta(days=а.діб)
    найстаріший = найстаріший_доступний(main_sha)
    неглибокий = _текст(git("rev-parse", "--is-shallow-repository").stdout).strip() == "true"
    if неглибокий and (найстаріший is None or найстаріший > від):
        print(f"не виміряно: історія main неглибока, найстаріший коміт {найстаріший and _utc(найстаріший)} новіший за "
              f"початок вікна {_utc(від)}. Догрузи: git fetch --shallow-since={(від - timedelta(days=1)).date()} origin main")
        return 2
    тіла, попередження = прочитати_тіла(а.тіла) if а.тіла else (None, [])
    надрукувати(main_sha, від, зараз, лічити(main_sha, від, зараз, тіла), попередження, а.пари)
    return 0


if __name__ == "__main__":
    sys.exit(main())
