РЕЄСТР_ШЛЯХ = "аудит/проби/живі_сцени.txt"
ДОВІРЕНИЙ_АВТОР = "mightyrochy"
ТЕМА_PR = re.compile(r"\(#([1-9][0-9]*)\)$")
ЗЛИТТЯ_PR = re.compile(r"^Merge pull request #([1-9][0-9]*) from ([^/\s]+)/")
ЧУЖА_МЕЖА = re.compile(r"(?m)^.*ПЕРЕВІРЕНО ЗБІРКУ.*[0-9a-f]{40}")
МЕЖА_ЗБІРКИ = re.compile(r"(?m)^ПЕРЕВІРЕНО ЗБІРКУ: ([0-9a-f]{40})\r?$")
НЕ_ПОТРІБЕН = re.compile(r"не\s+потріб", re.IGNORECASE)

# --- Розбір рядка: дослівний повтор Get-LiveSceneRegistry і Get-LiveAfterLines (queue_lanes.ps1) ------------------
# .NET: Char.IsWhiteSpace і `\s` — категорії Zs, Zl, Zp, U+0009–U+000D і U+0085 (Python `str.isspace` ширший: ще \x1c–\x1f).
_ПРОБІЛИ_NET = "\t\n\v\f\r\x85\x20\xa0\u1680\u2000\u2001\u2002\u2003\u2004\u2005\u2006\u2007\u2008\u2009\u200a" \
               "\u2028\u2029\u202f\u205f\u3000"
_S = "[" + re.escape(_ПРОБІЛИ_NET) + "]"
_ПОЧАТОК_РЯДКА = re.compile(r"^[-*+>#_" + re.escape(_ПРОБІЛИ_NET) + r"]*ЖИВИЙ ПІСЛЯ")
_МЕЖА_ПРОДОВЖЕННЯ = re.compile(r"^(?:ЖИВИЙ ПІСЛЯ|[-*+>#_`~]|\d+[.)]" + _S + r"|\|)")
_ПОВНИЙ_РЯДОК = re.compile(r"^ЖИВИЙ ПІСЛЯ: (.*)$")


def _обрізати(текст, лише=None):
    """`String.Trim()` .NET: пробіли за Char.IsWhiteSpace."""
    return текст.strip(_ПРОБІЛИ_NET if лише is None else лише)


def _велика_літера(символ):
    """`\\p{Lu}` .NET на одному UTF-16 знаку: символ поза BMP — сурогат, не Lu."""
    return ord(символ) <= 0xFFFF and unicodedata.category(символ) == "Lu"


def _межа_продовження(наступний):
    """`^(?:ЖИВИЙ ПІСЛЯ|[-*+>#_`~]|\\d+[.)]\\s|\\p{Lu}[^:]*:|\\|)`: гілку `\\p{Lu}[^:]*:` .NET перевіряємо вручну."""
    if _МЕЖА_ПРОДОВЖЕННЯ.match(наступний):
        return True
    return bool(наступний) and _велика_літера(наступний[0]) and ":" in наступний[1:]


def _голий_id(ід):
    """`^[\\p{L}\\p{Nd}_-]+$` .NET (UTF-16: символ поза BMP — сурогати, не літера)."""
    if not ід:
        return False
    for символ in ід:
        if символ in "_-":
            continue
        if ord(символ) > 0xFFFF:
            return False
        категорія = unicodedata.category(символ)
        if not (категорія.startswith("L") or категорія == "Nd"):
            return False
    return True


def реєстр_сцен(текст):
    """Get-LiveSceneRegistry: id — перше поле до «|», режим — п'яте; `#` і короткі рядки пропущено.
    Хештаблиця PowerShell нечутлива до регістру ключа: ключ — перше написання, режим — останнє."""
    ключі, режими = {}, {}
    for рядок in (текст or "").split("\n"):
        рядок = рядок.rstrip("\r").lstrip("\ufeff")
        if not _обрізати(рядок) or _обрізати(рядок).startswith("#"):
            continue
        поля = рядок.split("|")
        if len(поля) < 5:
            continue
        ід, нечутливий = _обрізати(поля[0]), _обрізати(поля[0]).lower()
        ключі.setdefault(нечутливий, ід)
        режими[нечутливий] = _обрізати(поля[4])
    return {ключі[к]: режими[к] for к in ключі}


def рядки_живий_після(тіло, реєстр):
    """Get-LiveAfterLines: рядок, що починається з `ЖИВИЙ ПІСЛЯ` (після пробілів, маркера списку чи виділення), або
    розібрано повністю (id, питання, режим), або в ньому `error` — тексти вад ті самі, що в обгортці."""
    результат = []
    рядки = (тіло or "").split("\n")
    і = 0
    while і < len(рядки):
        рядок = _обрізати(рядки[і])
        if not _ПОЧАТОК_РЯДКА.match(рядок):
            і += 1
            continue
        перший = і
        while і + 1 < len(рядки):
            наступний = _обрізати(рядки[і + 1])
            if not наступний or _межа_продовження(наступний):
                break
            рядок += " " + наступний
            і += 1
        пункт = {"line": рядок, "first": перший, "last": і, "id": "", "question": "", "mode": "", "error": ""}
        повний = _ПОВНИЙ_РЯДОК.match(рядок)
        if not повний:
            пункт["error"] = "рядок має починатися з «ЖИВИЙ ПІСЛЯ: » без маркера списку, виділення чи пропущеної двокрапки"
        else:
            решта = повний.group(1)
            де = решта.find(" — ")
            if де < 0:
                пункт["error"] = "нема « — » після id"
            else:
                ід = _обрізати(решта[:де])
                питання = _обрізати(решта[де + 3:])
                if not _голий_id(ід):
                    пункт["error"] = "id «" + ід + "» не голий: лише літери, цифри, _ і -, без лапок, зворотних лапок і пояснень"
                elif ід not in реєстр:
                    пункт["error"] = "id «" + ід + "» нема першим полем аудит/проби/живі_сцени.txt"
                elif not питання:
                    пункт["error"] = "порожнє питання після « — »"
                else:
                    пункт.update(id=ід, question=питання, mode=реєстр[ід])
        результат.append(пункт)
        і += 1
    return результат


# --- git ----------------------------------------------------------------------------------------------------------
def git(*аргументи, вхід=None, перевірити=True):
    """Один виклик git з `core.quotepath=false` (кириличні шляхи — як є)."""
    готово = subprocess.run(["git", "-c", "core.quotepath=false", *аргументи], input=вхід, capture_output=True,
                            check=False)
    if перевірити and готово.returncode != 0:
        raise RuntimeError("git " + " ".join(аргументи) + ": " + готово.stderr.decode("utf-8", "replace").strip())
    return готово


def _текст(байти):
    return байти.decode("utf-8", "replace")


def _час(iso):
    return datetime.fromisoformat(iso.replace("Z", "+00:00")).astimezone(timezone.utc)


def злиття_вікна(main, від, до):
    """Злиті PR — коміти першого батька `main` з датою коміту ≥ `від`. Сквош: тема `… (#N)`, повідомлення — його
    тіло, автор — автор PR. Коміт злиття (`Merge pull request #N from <власник>/<гілка>` чи своя назва `… (#N)`, два
    батьки): повідомлення — коміти гілки (`батько1..батько2`), довіра — власник гілки чи автор. Інші коміти (збірка,
    згортання дошки) — не PR. Усі коміти — і для злиттів за часом (`злиття_за_часом`)."""
    вивід = _текст(git("log", "--first-parent", "--since=" + від.isoformat(), "--until=" + до.isoformat(),
                       "--format=%H%x1f%cI%x1f%an%x1f%P%x1f%s%x1f%B%x1e", main).stdout)
    злиття, усі = [], []
    for запис in вивід.split("\x1e"):
        запис = запис.lstrip("\n")
        if not запис:
            continue
        sha, час, автор, батьки, тема, тіло = запис.split("\x1f", 5)
        батьки = батьки.split()
        усі.append((_час(час), sha))
        гілка, номер = ЗЛИТТЯ_PR.match(тема), ТЕМА_PR.search(тема)
        if гілка:
            pr, автор = int(гілка.group(1)), гілка.group(2)
        elif номер:
            pr = int(номер.group(1))
        else:
            continue
        if len(батьки) == 2:
            тіло = _текст(git("log", "--format=%B%x1e", батьки[0] + ".." + батьки[1]).stdout)
        злиття.append({"sha": sha, "час": _час(час), "автор": автор, "pr": pr, "тіло": тіло})
    return злиття, усі


def злиття_за_часом(усі, коли):
    """PR, влитий іншим PR (пачка), свого коміту злиття не має: його злиття — останній коміт першого батька `main`
    з часом не пізніше за `merged_at` (GitHub ставить його тієї ж секунди чи трохи пізніше за коміт)."""
    придатні = [(час, sha) for час, sha in усі if час <= коли]
    return max(придатні)[1] if придатні else ""


def прочитати_тіла(шляхи):
    """Тіла PR з файлів: потік JSON-значень — відповідь пошуку (`items`, `total_count`), список PR чи один PR.
    Повертає {номер: {"тіло", "логін"}} і попередження (неповна відповідь пошуку)."""
    тіла, попередження = {}, []
    декодер = json.JSONDecoder()
    for шлях in шляхи:
        with open(шлях, encoding="utf-8") as ф:
            текст = ф.read()
        позиція, пунктів, заявлено = 0, 0, 0
        while True:
            while позиція < len(текст) and текст[позиція].isspace():
                позиція += 1
            if позиція >= len(текст):
                break
            значення, позиція = декодер.raw_decode(текст, позиція)
            if isinstance(значення, dict) and "items" in значення:
                заявлено = max(заявлено, int(значення.get("total_count") or 0))
                значення = значення["items"]
            for pr in значення if isinstance(значення, list) else [значення]:
                if not isinstance(pr, dict) or not isinstance(pr.get("number"), int):
                    continue
                пунктів += 1
                злито = pr.get("merged_at") or (pr.get("pull_request") or {}).get("merged_at")
                тіла[pr["number"]] = {"тіло": pr.get("body") or "", "логін": (pr.get("user") or {}).get("login", ""),
                                      "злито": _час(злито) if злито else None}
        if заявлено > пунктів:
            попередження.append(f"{шлях}: пошук знайшов {заявлено}, у файлі {пунктів} — дочитай сторінки")
    return тіла, попередження


def команда_тіл(від):
    """Один пошук GitHub дає тіла всіх злитих PR вікна з «ЖИВИЙ ПІСЛЯ» (по 100 на сторінку)."""
    запит = (f"repo:mightyrochy/kod-shi-data is:pr is:merged merged:>={від.strftime('%Y-%m-%dT%H:%M:%SZ')} "
             f"\"ЖИВИЙ ПІСЛЯ\" in:body")
    return (f"for p in 1 2 3; do gh api -X GET search/issues -f q='{запит}' -f per_page=100 -f page=$p; done "
            f"> /tmp/тіла.json")


def найстаріший_доступний(main):
    """Час найстарішого коміту історії `main`, яку має клон (неглибокий клон обриває її)."""
    вивід = _текст(git("log", "--first-parent", "--format=%cI", main).stdout).split()
    return _час(вивід[-1]) if вивід else None


def прочитати_файли(main, шляхи):
    """Вміст файлів дерева `main` одним `git cat-file --batch`."""
    if not шляхи:
        return {}
    запит = "".join(main + ":" + шлях + "\n" for шлях in шляхи).encode("utf-8")
    вивід = git("cat-file", "--batch", вхід=запит).stdout
    файли, позиція = {}, 0
    for шлях in шляхи:
        кінець = вивід.index(b"\n", позиція)
        шапка = вивід[позиція:кінець].split()
        позиція = кінець + 1
        if len(шапка) < 3 or шапка[1] != b"blob":
            continue
        розмір = int(шапка[2])
        файли[шлях] = _текст(вивід[позиція:позиція + розмір])
        позиція += розмір + 1
    return файли


def предки(sha, кеш):
    """Множина комітів, досяжних зі збірки `sha` (у межах історії клону); None — збірки в клоні нема."""
    if sha not in кеш:
        готово = git("rev-list", sha, "--", перевірити=False)
        кеш[sha] = set(_текст(готово.stdout).split()) if готово.returncode == 0 else None
    return кеш[sha]


def _згадує(текст, ід):
    return re.search(r"(?<![\w-])" + re.escape(ід) + r"(?![\w-])", текст) is not None


def звіти(main, змінені_у_вікні):
    """Усі `ЗВІТ.md` під `аудит/` голови `main`: межа збірки (чи вадна), текст і теки поруч."""
    шляхи = [ш for ш in _текст(git("ls-tree", "-r", "--name-only", main, "--", "аудит").stdout).splitlines()]
    звітні = [ш for ш in шляхи if ш.rsplit("/", 1)[-1] == "ЗВІТ.md"]
    тексти = прочитати_файли(main, звітні)
    теки_звітів = {ш.rpartition("/")[0] for ш in звітні}
    теки_поруч = {}
    for ш in шляхи:
        частини = ш.split("/")
        for к in range(1, len(частини)):
            батько = "/".join(частини[:к])
            if батько in теки_звітів:
                теки_поруч.setdefault(батько, set()).add(частини[к])
    результат = []
    for шлях in звітні:
        текст = тексти.get(шлях, "")
        межі = МЕЖА_ЗБІРКИ.findall(текст)
        тека = шлях.rpartition("/")[0]
        результат.append({
            "шлях": шлях, "текст": текст, "сусіди": теки_поруч.get(тека, set()),
            "збірка": межі[0] if len(межі) == 1 else "",
            "кілька_меж": len(межі) > 1,
            "межа_не_за_форматом": not межі and ЧУЖА_МЕЖА.search(текст) is not None,
            "у_вікні": шлях in змінені_у_вікні,
        })
    return результат


def змінені_файли(main, від):
    """Файли, змінені комітами першого батька `main` від `від`, з часом першої зміни у вікні."""
    вивід = _текст(git("log", "--first-parent", "--since=" + від.isoformat(), "--name-only", "--format=\x1e%cI",
                       main).stdout)
    файли = {}
    for запис in вивід.split("\x1e"):
        рядки = [р for р in запис.split("\n") if р]
        if not рядки:
            continue
        час = _час(рядки[0])
        for шлях in рядки[1:]:
            if шлях not in файли or час < файли[шлях]:
                файли[шлях] = час
    return файли


# --- лічба ----------------------------------------------------------------------------------------------------------
def лічити(main, від, зараз, тіла=None):
    """Питання (PR × сцена) вікна, прогнані й ні; вадні рядки; що не виміряно. `тіла` — {номер: {"тіло", "логін"}}
    з файлу (джерело плану обгортки); None — рядки з повідомлень злиття."""
    реєстр = реєстр_сцен(прочитати_файли(main, [РЕЄСТР_ШЛЯХ]).get(РЕЄСТР_ШЛЯХ, ""))
    if not реєстр:
        raise RuntimeError("реєстр " + РЕЄСТР_ШЛЯХ + " порожній на " + main)
    злиття, усі_коміти = злиття_вікна(main, від, зараз)
    за_часом = []
    if тіла is not None:
        злиті = {коміт["pr"] for коміт in злиття}
        for номер, т in sorted(тіла.items()):
            if номер in злиті or т["злито"] is None or not (від <= т["злито"] <= зараз):
                continue
            sha = злиття_за_часом(усі_коміти, т["злито"])
            if sha:
                за_часом.append(номер)
                злиття.append({"sha": sha, "час": т["злито"], "автор": т["логін"], "pr": номер, "тіло": ""})
    змінені = змінені_файли(main, від)
    усі_звіти = звіти(main, змінені)
    кеш = {}
    з_межею = []
    for звіт in усі_звіти:
        if звіт["збірка"]:
            звіт["предки"] = предки(звіт["збірка"], кеш)
            з_межею.append(звіт)
    питання, вадні, чужі, лише_в_повідомленні = {}, [], [], []
    pr_злитих = рядків = 0
    pr_з_рядком = set()
    for коміт in злиття:
        pr = коміт["pr"]
        pr_злитих += 1
        if тіла is None:
            пункти = рядки_живий_після(коміт["тіло"], реєстр)
        else:
            пункти = рядки_живий_після(тіла[pr]["тіло"], реєстр) if pr in тіла else []
            if pr not in тіла and коміт["автор"] == ДОВІРЕНИЙ_АВТОР and any(
                    not п["error"] for п in рядки_живий_після(коміт["тіло"], реєстр)):
                лише_в_повідомленні.append(pr)
            if pr in тіла and тіла[pr]["логін"] != ДОВІРЕНИЙ_АВТОР and пункти:
                чужі.append((pr, тіла[pr]["логін"]))
                continue
        if not пункти:
            continue
        if коміт["автор"] != ДОВІРЕНИЙ_АВТОР:
            чужі.append((pr, коміт["автор"]))
            continue
        pr_з_рядком.add(pr)
        for пункт in пункти:
            рядків += 1
            if пункт["error"]:
                if any(в["pr"] == pr and в["рядок"] == пункт["line"] for в in вадні):
                    continue
                вадні.append({"pr": pr, "рядок": пункт["line"], "вада": пункт["error"],
                              "не_потрібен": bool(НЕ_ПОТРІБЕН.search(пункт["line"]))})
                continue
            ключ = (pr, пункт["id"])
            if ключ not in питання:
                питання[ключ] = {"pr": pr, "сцена": пункт["id"], "режим": пункт["mode"], "злиття": коміт["sha"],
                                 "час": коміт["час"], "звіти": []}
    for п in питання.values():
        for звіт in з_межею:
            if звіт["предки"] and п["злиття"] in звіт["предки"] and (
                    _згадує(звіт["текст"], п["сцена"]) or п["сцена"] in звіт["сусіди"]):
                п["звіти"].append(звіт["шлях"])
    непрогнані = sorted((п for п in питання.values() if not п["звіти"]), key=lambda п: (п["час"], п["pr"], п["сцена"]))
    без_межі = []
    for звіт in усі_звіти:
        if звіт["збірка"] or not звіт["у_вікні"]:
            continue
        час_звіту = змінені[звіт["шлях"]]
        згадано = [п for п in непрогнані if п["час"] < час_звіту and (
            _згадує(звіт["текст"], п["сцена"]) or п["сцена"] in звіт["сусіди"])]
        if згадано:
            без_межі.append({"шлях": звіт["шлях"], "час": час_звіту, "згадано": len(згадано)})
    злиті_номери = {коміт["pr"] for коміт in злиття}
    return {
        "з_тіл": тіла is not None, "лише_в_повідомленні": sorted(лише_в_повідомленні), "за_часом": за_часом,
        "тіла_поза_main": sorted(н for н, т in (тіла or {}).items() if н not in злиті_номери
                                 and (т["злито"] is None or від <= т["злито"] <= зараз)),
        "pr_злитих": pr_злитих, "pr_з_рядком": len(pr_з_рядком), "рядків": рядків, "питання": питання,
        "непрогнані": непрогнані, "вадні": вадні, "чужі": чужі, "без_межі": без_межі,
        "не_за_форматом": [з["шлях"] for з in усі_звіти
                           if з["у_вікні"] and (з["межа_не_за_форматом"] or з["кілька_меж"])],
        "збірки_нема": [з["шлях"] for з in з_межею if з["предки"] is None],
        "звітів_з_межею": len(з_межею),
    }


def _utc(час):
    return час.strftime("%Y-%m-%d %H:%MZ")


def надрукувати(main_sha, від, зараз, лічба, попередження=()):
    м = len(лічба["питання"])
    н = м - len(лічба["непрогнані"])
    print(f"Вікно: {_utc(від)} — {_utc(зараз)}; main {main_sha}")
    print("Джерело рядків: " + ("тіла PR із файлу (як у плані обгортки)" if лічба["з_тіл"] else
                                "повідомлення злиття — тіл PR не дано, M — нижня межа"))
    print(f"Злитих PR у вікні: {лічба['pr_злитих']}, з рядком ЖИВИЙ ПІСЛЯ: {лічба['pr_з_рядком']}; рядків у "
          f"{'тілах PR' if лічба['з_тіл'] else 'повідомленнях злиття'}: {лічба['рядків']}, вадних різних: {len(лічба['вадні'])} "
          f"(з них «не потрібен»: {sum(1 for в in лічба['вадні'] if в['не_потрібен'])})")
    print(f"Питань (PR × сцена): {м}; прогнано: {н}; звітів з ПЕРЕВІРЕНО ЗБІРКУ у main: {лічба['звітів_з_межею']}")
    if лічба["непрогнані"]:
        print("Непрогнані (PR, злито UTC, сцена, режим, годин від злиття):")
        for п in лічба["непрогнані"]:
            годин = (зараз - п["час"]).total_seconds() / 3600
            print(f"  #{п['pr']}\t{_utc(п['час'])}\t{п['сцена']}\t{п['режим']}\t{годин:.1f}")
    if лічба["вадні"]:
        print("Вадні рядки (не питання: план їх не прожене):")
        for в in лічба["вадні"]:
            print(f"  #{в['pr']}\t{в['вада']}\t{в['рядок'][:120]}")
    print("Не виміряно:")
    if not лічба["з_тіл"]:
        print("  тіла PR — не в git; дай --тіла <файл>, файл — одна команда: " + команда_тіл(від))
    for рядок in попередження:
        print("  " + рядок)
    for pr in лічба["лише_в_повідомленні"]:
        print(f"  #{pr}: рядок ЖИВИЙ ПІСЛЯ є в повідомленні злиття, а у файлі тіл PR нема — не рахується")
    if лічба["за_часом"]:
        print(f"  свого коміту злиття в main нема (влито іншим PR) — злиття взято за часом merged_at: "
              f"{len(лічба['за_часом'])} PR: " + ", ".join("#" + str(н) for н in лічба["за_часом"][:30]))
    if лічба["тіла_поза_main"]:
        print("  PR із файлу тіл, яких нема серед злиттів вікна в історії main (вікно, неглибока історія чи старий "
              "main): " + ", ".join("#" + str(н) for н in лічба["тіла_поза_main"][:30]))
    for з in лічба["без_межі"]:
        print(f"  звіт без ПЕРЕВІРЕНО ЗБІРКУ (не рахується прогнаним): {з['шлях']} ({_utc(з['час'])}), згадує сцен "
              f"непрогнаних питань, злитих раніше за нього: {з['згадано']}")
    for шлях in лічба["не_за_форматом"]:
        print(f"  ПЕРЕВІРЕНО ЗБІРКУ не за форматом «ПЕРЕВІРЕНО ЗБІРКУ: <SHA>» окремим рядком (не рахується): {шлях}")
    for шлях in лічба["збірки_нема"]:
        print(f"  збірки звіту нема в історії клону: {шлях}")
    for pr, автор in лічба["чужі"]:
        print(f"  #{pr}: автор {автор}, не {ДОВІРЕНИЙ_АВТОР} — пропущено, як у плані обгортки")
    print(f"прогнано: {н} з {м}" + ("" if лічба["з_тіл"] else " (без тіл PR: M — нижня межа)"))


def main(аргументи=None):
    розбір = argparse.ArgumentParser(description="Питання ЖИВИЙ ПІСЛЯ злитого: прогнано N з M (лише git).")
    розбір.add_argument("--діб", type=float, default=7.0, help="вікно злиття в добах до --зараз (типово 7)")
    розбір.add_argument("--від", help="початок вікна ISO (UTC), замість --діб")
    розбір.add_argument("--зараз", help="кінець вікна й відлік годин ISO (UTC); типово — годинник машини")
    розбір.add_argument("--main", default="", help="гілка чи коміт main (типово origin/main, нема — main)")
    розбір.add_argument("--тіла", action="append", default=[], help="файл тіл PR (відповідь пошуку GitHub); можна кілька")
    а = розбір.parse_args(аргументи)
    os.chdir(_текст(git("rev-parse", "--show-toplevel").stdout).strip())
    main_ref = а.main or next(
        (р for р in ("origin/main", "main") if git("rev-parse", "--verify", "-q", р, перевірити=False).returncode == 0),
        "HEAD")
    main_sha = _текст(git("rev-parse", main_ref).stdout).strip()
    зараз = _час(а.зараз) if а.зараз else datetime.now(timezone.utc)
    від = _час(а.від) if а.від else зараз - timedelta(days=а.діб)
    найстаріший = найстаріший_доступний(main_sha)
    неглибокий = _текст(git("rev-parse", "--is-shallow-repository").stdout).strip() == "true"
    if неглибокий and (найстаріший is None or найстаріший > від):
        print(f"не виміряно: історія main неглибока, найстаріший коміт {найстаріший and _utc(найстаріший)} новіший за "
              f"початок вікна {_utc(від)}. Догрузи: git fetch --shallow-since={(від - timedelta(days=1)).date()} origin main")
        return 2
    тіла, попередження = прочитати_тіла(а.тіла) if а.тіла else (None, [])
    надрукувати(main_sha, від, зараз, лічити(main_sha, від, зараз, тіла), попередження)
    return 0


if __name__ == "__main__":
    sys.exit(main())
