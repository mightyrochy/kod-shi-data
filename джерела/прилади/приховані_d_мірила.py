# ───────────────────────────── ознаки ─────────────────────────────
_ПАДАЄ_PY = re.compile(r"^\s*assert\b|\braise\b|sys\.exit\(\s*(?!0\s*\)|\))[^)]|\bexit\(\s*[1-9]|SystemExit\(\s*[1-9]"
                       r"|os\._exit\(\s*[1-9]", re.M)
_ПАДАЄ_JS = re.compile(r"process\.exit\(\s*(?!0\s*\))[^)]|process\.exitCode\s*=|\bthrow\b|assert[.(]")
_ПАДАЄ_SH = re.compile(r"\bexit\s+[1-9]|set\s+-[a-z]*e|\bthrow\b|\$ErrorActionPreference\s*=\s*['\"]Stop")
_ВИХІД0 = re.compile(r"sys\.exit\(\s*0?\s*\)|\bexit\(\s*0\s*\)|SystemExit\(\s*0?\s*\)|process\.exit\(\s*0\s*\)"
                     r"|^\s*exit\s+0\b")
_БРАК = re.compile(r"exists|нема|відсут|пропуск|skip|SKIP|без входу|БЕЗ ВХОДУ|ImportError|ModuleNotFound|except|"
                   r"not found|ENOENT|catch", re.I)
_ТЕКСТ = re.compile(r"(?:open|read_text|readFileSync|Path)\([^\n]*\.(?:py|js|html)\b"
                    r"|ast\.parse\(|inspect\.getsource|getsource\(|glob\([^\n]*\*\.py")
_ЗАГЛУШКА = re.compile(r"\bmock\b|monkeypatch|unittest\.mock|заглушк|\bstub|\bfake", re.I)
_ЗАПИС = re.compile(r"аудит/проби/|аудит', 'проби|записан|replay|\.jsonl|автоживий", re.I)
_ФІКСТУРА = re.compile(r"стенд_вх|каталог_brief|фікстур", re.I)
_МОДЕЛЬ = re.compile(r"ollama|/api/chat|/v1/chat|/api/generate|localhost:11434|ноутбук|anthropic|openai"
                     # CLI моделі підпроцесом і LM Studio ноутбука (вибірка Д5 31.10: `розмова2_проба.py` кличе
                     # `claude -p`, `речі_голосом_живий_5742.py` — `MODEL_URL`)
                     r"|\[\s*[\"']claude[\"']|\bclaude -p\b|MODEL_URL|127\.0\.0\.1:1234", re.I)
_ЖИВЕ = re.compile(r"живий|живого|наживо|живим|живому", re.I)
_ЖИВИЙ_ШЛЯХ = re.compile(r"жив\w*[ _](?:шлях|вход|вхід|катало[гз]|фід)\w*", re.I)


def _докстрінг(текст):
    м = re.search(r'"""(.*?)"""|\'\'\'(.*?)\'\'\'|/\*\*?(.*?)\*/', текст, re.S)
    if not м:
        return ""
    return (м.group(1) or м.group(2) or м.group(3) or "")[:600]


def _підміна(текст, продукт):
    """Присвоєння атрибуту імпортованого модуля продукту: `модуль.ф = …` (не `==`)."""
    імпорти = set(re.findall(r"^\s*import\s+([\w, ]+)", текст, re.M))
    імена = set()
    for р in імпорти:
        for ч in р.split(","):
            ч = ч.strip().split(" as ")
            if ч[0] in продукт:
                імена.add(ч[-1].strip())
    for м in re.finditer(r"^\s*import\s+(\w+)\s+as\s+(\w+)", текст, re.M):
        if м.group(1) in продукт:
            імена.add(м.group(2))
    місця = []
    for і, р in enumerate(текст.splitlines(), 1):
        м = re.match(r"\s*(\w+)\.(\w+)\s*=(?!=)", р)
        if м and м.group(1) in імена:
            місця.append(і)
    return місця


def _проза(т, розш):
    """Номери рядків докстрінгів і коментарів: ознаки коду там не шукаємо (опис ≠ дія)."""
    рядки = т.splitlines()
    вихід = {і for і, р in enumerate(рядки, 1) if re.match(r"\s*(#|//|\*|/\*)", р)}
    if розш == "py":
        import ast
        import warnings
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                дерево = ast.parse(т)
        except SyntaxError:
            return вихід
        for в in ast.walk(дерево):
            if isinstance(в, ast.Expr) and isinstance(getattr(в, "value", None), ast.Constant) \
                    and isinstance(в.value.value, str):
                вихід.update(range(в.lineno, (в.end_lineno or в.lineno) + 1))
    return вихід


def ознаки(вид, шлях, продукт):
    т = _текст(шлях)
    рядки = т.splitlines()
    розш = шлях.rsplit(".", 1)[-1]
    проза = _проза(т, розш)
    код = "\n".join("" if і in проза else р for і, р in enumerate(рядки, 1))
    if розш == "py":
        падає = bool(_ПАДАЄ_PY.search(код))
    elif розш == "js":
        падає = bool(_ПАДАЄ_JS.search(код))
    else:
        падає = bool(_ПАДАЄ_SH.search(код))
    пропуски = []
    кінець = len(рядки) - 3
    for і, р in enumerate(рядки, 1):
        if і >= кінець or і in проза or not _ВИХІД0.search(р):
            continue
        вікно = "\n".join(рядки[max(0, і - 4):і])
        if _БРАК.search(вікно):
            пропуски.append(і)
    док = _докстрінг(т)
    ім = os.path.basename(шлях)
    імпорти = set()
    for м in re.finditer(r"^\s*(?:from\s+(\w+)\s+import|import\s+([\w, ]+))", код, re.M):
        for ч in (м.group(1) or м.group(2) or "").split(","):
            імпорти.add(ч.strip().split(" ")[0])
    викликає = bool(імпорти & продукт) or bool(re.search(r"require\([^)]*(?:джерела|\.\./|\./)[^)]*\)"
                                                          r"|importScripts|pyodide|runPython|subprocess"
                                                          # виконує код продукту без імпорту (вибірка Д3 31.10:
                                                          # 4 з 10 хибних — браузер, JSDOM, `new Function`, `exec`;
                                                          # друга — 2 з 11: `import(` модуля, `exec_module`)
                                                          r"|chromium|playwright|puppeteer|runScripts|new Function\("
                                                          r"|\bvm\.(?:run|Script)|\bexec\(|compile\([^)]*['\"]exec|\bimport\(|exec_module", код))
    return {
        "падає": падає,
        "пропуск": пропуски,
        "текст": [і for і, р in enumerate(рядки, 1) if і not in проза and _ТЕКСТ.search(р)],
        "викликає": викликає,
        "заглушка": [і for і, р in enumerate(рядки, 1) if і not in проза and _ЗАГЛУШКА.search(р)] + (
            _підміна(т, продукт) if розш == "py" else []),
        "запис": bool(_ЗАПИС.search(код)),
        "фікстура": bool(_ФІКСТУРА.search(код)),
        "модель": bool(_МОДЕЛЬ.search(код)),
        "живе_імʼя": bool(_ЖИВЕ.search(ім) or _ЖИВЕ.search(док.strip().split("\n")[0])),
        "живий_шлях": bool(_ЖИВИЙ_ШЛЯХ.search(ім + "\n" + док)),
        "рядків": len(рядки),
    }


