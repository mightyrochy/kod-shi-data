    print(f"  ознаки поставлено: {len(дані)}/{len(дані)} файлів, {len(кроки)}/{len(кроки)} кроків, "
          f"{len(дошка)}/{len(дошка)} рядків")
    print("\nДЖЕРЕЛО ВХОДУ мірил-файлів (може кілька):")
    for ключ in ("модель", "запис", "фікстура"):
        print(f"  {ключ}: {sum(о[ключ] for о in дані)}")
    print(f"  заглушка: {sum(bool(о['заглушка']) for о in дані)}; текст коду: {sum(bool(о['текст']) for о in дані)}")
    print(f"  без вердикту провалу: {sum(not о['падає'] for о in дані)}")
    хто = Counter()
    for о in дані:
        хто[("CI" if "CI" in о["хто"] else "батарея" if "батарея" in о["хто"] else
             "лічба" if "лічба" in о["хто"] else "правило" if "правило" in о["хто"] else "нікого", о["вид"])] += 1
    print("\nХТО ЗАПУСКАЄ (найсильніший запускач, вид):")
    for (к, в), н in sorted(хто.items()):
        print(f"  {к:8} {в:3} {н}")
    if а.лічба:
        стани = {}
        for р in open(а.лічба, encoding="utf-8"):
            try:
                з = json.loads(р)
            except ValueError:
                continue
            стани[os.path.normpath(з["проба"])] = з["rc"]
        rc = Counter("0" if в == 0 else "124" if в == 124 else "≠0" for в in стани.values())
        print(f"\nПРОГІН ПРОБ (лічба_проб): зміряно {len(стани)}; rc 0 {rc['0']}, стеля {rc['124']}, червоних {rc['≠0']}")
        без = [о for о in дані if о["вид"] == "П" and not о["падає"]]
