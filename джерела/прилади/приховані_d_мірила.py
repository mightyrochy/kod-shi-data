def _тексти(шаблони):
    вихід = {}
    for ш in шаблони:
        for ф in glob.glob(os.path.join(КОРІНЬ, ш), recursive=True):
            if os.path.isfile(ф):
                вихід[_в(ф)] = _текст(ф)
    return вихід


def хто_запускає(одиниці):
    ci = _тексти([".github/workflows/*.yml"])
    глоби_ci = set()
    for т in ci.values():
        for м in re.finditer(r"([\wА-Яа-яІіЇїЄєҐґ/._-]*\*[\wА-Яа-яІіЇїЄєҐґ/._*-]*\.(?:py|js))", т):
            глоби_ci.add(м.group(1))
    батареї = {к: в for к, в in _тексти(["джерела/батарея_*.py", "джерела/прилади/розділи_гейтів.py",
                                         "джерела/стенд_знімок.py", "джерела/тест_*.py", "джерела/тест_*.js",
                                         "джерела/audit_*.py", "джерела/gate_*.py"]).items()}
    правила = _тексти(["аудит/**/*.md", "*.md", "джерела/*.md"])
    ci_разом = "\n".join(ci.values())
    for к in list(батареї):
        батареї[к] = "\n".join(р for р in батареї[к].splitlines()
                               if not re.match(r"\s*(#|//|from\s|import\s)", р))
    пр_разом = "\n".join(правила.values())
    import fnmatch
    вихід = {}
    for вид, ф in одиниці:
        ім = os.path.basename(ф)
        відн = _в(ф)
        хто = []
        # glob без теки (`*.js` у `node --check`, `py_compile`) — перевірка синтаксису, не запуск мірила
        if ім in ci_разом or any("/" in г and fnmatch.fnmatch(відн, "*" + г) for г in глоби_ci):
            хто.append("CI")
        if any(ім in т for к, т in батареї.items() if not к.endswith(ім)):
            хто.append("батарея")
        if вид == "П" and відн.endswith(".py"):
            хто.append("лічба")
        if ім in пр_разом or ім[:-3] in пр_разом:
            хто.append("правило")
        вихід[ф] = хто
    return вихід


# ───────────────────────────── кроки CI ─────────────────────────────
def кроки_ci():
    """Крок — `- name:` у списку `steps`; ознаки: run, не-блокує (на кроці чи job), `|| true`."""
    кроки = []
    for ф in sorted(glob.glob(os.path.join(КОРІНЬ, ".github/workflows/*.yml"))):
        рядки = _текст(ф).splitlines()
        job_coe = False
        поточний = None
        for і, р in enumerate(рядки, 1):
            if re.match(r"^  [\w-]+:\s*$", р):
                job_coe = False
            if re.match(r"^    continue-on-error:\s*true", р):
                job_coe = True
            м = re.match(r"^      - name:\s*(.*)", р)
            if м:
                поточний = {"файл": _в(ф), "рядок": і, "імʼя": м.group(1).strip(), "run": False,
                            "не_блокує": job_coe, "або_true": [], "тіло": ""}
                кроки.append(поточний)
                continue
            if поточний is None:
                continue
            if re.match(r"^        run:", р):
                поточний["run"] = True
            if поточний["run"]:
                поточний["тіло"] += р + "\n"
            if re.match(r"^        continue-on-error:\s*true", р):
                поточний["не_блокує"] = True
            if "|| true" in р and поточний["run"]:
                поточний["або_true"].append(і)
    return кроки


# ───────────────────────────── дошка ─────────────────────────────
def рядки_дошки():
    вихід = []
    for і, р in enumerate(_текст(os.path.join(КОРІНЬ, "аудит/БЕКЛОГ.md")).splitlines(), 1):
        if not р.startswith("|"):
            continue
        д = re.search(r"доказ=(\w+)", р)
        if not д:
            continue
        н = re.match(r"\|\s*(\d+)\s*\|", р)
        ст = re.search(r"\*\*([А-ЯІЇЄҐA-Z-]+)", р)
        рід = re.search(r"рід=(\w+)", р)
        проби = set(re.findall(r"((?:аудит/|джерела/)?проби/[\w\-./]+?\.(?:py|js|mjs|sh))\b", р))
        вихід.append({"рядок": і, "номер": н.group(1) if н else "?", "статус": ст.group(1) if ст else "?",
                      "доказ": д.group(1), "рід": рід.group(1) if рід else "-", "проби": проби,
                      "мірило_в_рядку": bool(проби or re.search(r"[\w/]+\.(?:py|js|mjs)\b", р)), "текст": р})
    return вихід


