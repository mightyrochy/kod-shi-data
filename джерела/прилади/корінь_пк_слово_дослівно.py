# -*- coding: utf-8 -*-
"""Прилад кореня ПК-слово-дослівно: посилання правил роботи на джерело норми, що не тримає «під «власник» — лише його
слово».

Клас — `аудит/корені/ПК-слово-дослівно.md` («Клас місць», «Рішення менеджера 31.10»). Обсяг — 20 файлів за переліком
нижче (19 правил роботи частини (ґ) і `аудит/ПРОДУКТ.md` за рішенням менеджера 31.10; `аудит/СТАНДАРТ_КОДУ.md` — ні),
не пошук. Журнал `аудит/РІШЕННЯ_ВЛАСНИКА.md` — мірка, не обсяг.

ОДИНИЦЯ — зворот із джерелом у тексті файлу (не рядок і не правило: двоє посилань у реченні — дві одиниці), вид:
  власник     «власник»/«власника» і дата того самого звороту (до закритої дужки, «;», кінця речення чи 160 знаків),
              а між ними нема слова виду (тоді дата — того виду: «слову власника … → перепис 26.10» — «інше»);
  за-словом   «(менеджер ДД.ММ за словом власника ДД.ММ)» — форма виведеної норми з рішення менеджера 31.10;
  власник-б/д «власник» як джерело без дати — «(власник)», «— власник»;
  гола-дата   дата в дужках, а в її звороті (частина дужок до «;») перед датою нема слова виду й файлу-джерела ніде;
  інше        дата з видом у тому самому звороті (вимір, урок, проба, діагностика, перепис, ревізія, PR, менеджер…)
              чи з файлом-джерелом (`аудит/…`) — лише лічба.
Не дата: «3.10-1» (назва кроку), «python 3.11», «18.06.2026» (місяць поза 09–12), «31.10.2026» у дужках з роком.

КЛЮЧ одиниці — файл і нормований текст звороту: від початку речення (чи кінця попередньої одиниці того самого
речення) до кінця посилання, пробіли згорнуто. Рядок файлу в ключ не входить: правка вище не зсуває вердикт на чужий
зворот (паспорт, «Невдалі підходи»). Зворот змінено — ключ інший, вердикт треба писати заново.

МІСЦЕ — одиниця, що порушує інваріант (кожна лічиться раз; пункт — перший, що спрацював, у порядку нижче):
  п.1 (суд)   вид «власник», вердикт Ш чи І у даних приладу; одиниця «власник» без вердикту — теж місце («без
              вердикту»): нове посилання, якого не судили, храповик бачить як ріст;
  п.2         детерміновано: «власник-б/д»; «власник»/«за-словом» з датою, якої в журналі нема (заголовок розділу чи
              штамп запису «- **ДД.ММ…**»); суд: вердикт Д чи Н (дата чи слово не ті, «власник» на дії);
  п.3         детерміновано: «гола-дата» — і тоді, коли подію названо в реченні перед дужками (рішення менеджера 31.10).
Не місце: вердикт В (передає слово) чи НД («власник» у звороті — не джерело норми) без детермінованих пп.2–3; «інше».

ДАНІ ПРИЛАДУ — `аудит/корені/ПК-слово-дослівно-вердикти.tsv` (рядок `база:` паспорта): файл ⇥ ключ ⇥ вердикт ⇥ рядок
журналу ⇥ звідки вердикт ⇥ чому. Вердикти пише не автор правил — сесія лічби (рішення менеджера 31.10). Перша база —
перелік (ґ) на da4fc1da, перенесений за текстом звороту, і вердикти сесії лічби на одиниці без нього.

Запуск з кореня репозиторію (чи `--корінь <шлях>`):
  python3 джерела/прилади/корінь_пк_слово_дослівно.py                 місця, підсумок, останній рядок `місць: N`
  python3 джерела/прилади/корінь_пк_слово_дослівно.py --одиниці       одиниці: вид ⇥ файл:рядок ⇥ вердикт ⇥ пункт ⇥
                                                                       зворот ⇥ ключ
  python3 джерела/прилади/корінь_пк_слово_дослівно.py --самоперевірка зразки класу на штучному тексті
Вивід детермінований, код виходу 0 (храповик, `аудит/КОД.md`).
"""
import argparse
import os
import re
import sys

КОРІНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ЖУРНАЛ = "аудит/РІШЕННЯ_ВЛАСНИКА.md"
ВЕРДИКТИ = "аудит/корені/ПК-слово-дослівно-вердикти.tsv"

# Обсяг — перелік паспорта (частина (ґ): ядро, адаптери, файли ролей і їхні додатки, план і картина) і
# `аудит/ПРОДУКТ.md` (рішення менеджера 31.10: «у класі»). Файлу нема на дереві — пропуск із рядком у підсумку.
ОБСЯГ = ("AGENTS.md", "CLAUDE.md", "GEMINI.md", "аудит/CHATGPT.md", "аудит/НОУТБУК.md",
         "аудит/адаптери/CLAUDE_КЕРУВАННЯ.md", "аудит/адаптери/gemini/НАЛАШТУВАННЯ.md",
         "аудит/адаптери/gemini/ЧЕРГА.md", "аудит/адаптери/gemini/СПОСТЕРІГАЧ.md",
         "аудит/адаптери/gemini/m9v/ЩО_НАТИСНУТИ.md", "аудит/МЕНЕДЖЕР.md", "аудит/ДИСПЕТЧЕР.md",
         "аудит/ВИКОНАВЕЦЬ.md", "аудит/ПЕРЕВІРКА.md", "аудит/КОД.md", "аудит/МОДЕЛІ.md",
         "аудит/проби/живі_порядок.md", "аудит/ПЛАН.md", "аудит/КАРТИНА.md", "аудит/ПРОДУКТ.md")

ВЕРДИКТ_П1 = {"Ш", "І"}
ВЕРДИКТ_П2 = {"Д", "Н"}
ВЕРДИКТ_НЕ = {"В", "НД"}

# Дата ДД.ММ (місяці проєкту 09–12): не частина числа, версії, року чи назви кроку («3.10-1»).
_ДАТА = re.compile(r"(?<![\d.])(\d{1,2})\.(09|10|11|12)(?![\d]|\.\d|-\d)")
# Дата з роком («20.10.2026») — у журналі й у звороті «власник»; у проході дужок рік дату не робить (як лічба (ґ)).
_ДАТА_Р = re.compile(r"(?<![\d.])(\d{1,2})\.(09|10|11|12)(?![\d]|-\d)")
_ВЛАСНИК = re.compile(r"(?<![\w])(власник|власника)(?![\w])", re.I)
# Слово виду джерела (паспорт п.3: «вимір 26.10», «урок 08.10», «проба 25.10», «діагностика 26.10», «перепис 26.10»;
# решта — види, якими лічба (ґ) уже відділяла «інше»: ревізія, розбір, замір, прогін, знахідка, перевірка, PR, сесії,
# і прилад кореня; «відмови приладів 29–30.10» — подія, не вид джерела).
_ВИД = re.compile(r"вимір|урок|проб[аи]|діагностик|перепис|ревізі|розбір|замір|прогін|прогон|знахідк|перевірк"
                  r"|(?<![\w])PR(?![\w])|#\d|менеджер|диспетчер|прилад\w*\s+корен", re.I)
# Файл-джерело у звороті: шлях репозиторію (`аудит/передачі/…`, `аудит/корені/…`).
_ФАЙЛ = re.compile(r"`?(?:аудит|джерела|показ|\.github)/[^\s`)]+")
_ЗА_СЛОВОМ = re.compile(r"(менеджер|диспетчер)\w*\s+\d{1,2}\.\d{2}\s+за\s+слов\w*\s*$", re.I)
_ВЕРСІЯ = re.compile(r"(python|node|v|версі\w*)\s*$", re.I)


def _дати(текст, рік=False):
    return ["%02d.%s" % (int(д), м) for д, м in (_ДАТА_Р if рік else _ДАТА).findall(текст)]


def _межа(плаский, від, ліміт=160):
    """Кінець звороту від позиції: закрита дужка (включно), «;», кінець речення, абзац чи ліміт знаків."""
    м = re.search(r"\)|;|\.\s|\n\n", плаский[від:від + ліміт])
    if м:
        return від + м.start() + (1 if м.group(0) == ")" else 0)
    return min(len(плаский), від + ліміт)


_МЕЖА_РЕЧЕННЯ = re.compile(r"\n\s*\n(?:\s*(?:[-*]|\d+\.)\s)?|\n\s*(?:[-*]|\d+\.)\s|\n#+\s|\||[.!?…]\s+(?=[«\"(`*_\[A-ZА-ЯҐЄІЇ0-9])")


def _початок_речення(текст, поз):
    """Позиція початку речення, у якому стоїть `поз`: після абзацу, пункту переліку, заголовка, клітинки таблиці чи
    кінця попереднього речення."""
    поч = 0
    for м in _МЕЖА_РЕЧЕННЯ.finditer(текст, 0, поз):
        поч = м.end()
    return поч


def _кінець_речення(текст, поз):
    """Позиція кінця речення, у якому стоїть `поз` (крапку речення включно)."""
    м = _МЕЖА_РЕЧЕННЯ.search(текст, поз)
    if not м:
        return len(текст)
    return м.start() + (1 if текст[м.start()] in ".!?…" else 0)


def _нормувати(текст):
    return re.sub(r"\s+", " ", текст).strip()


def _відкрита_дужка(текст, поз):
    """Позиція «(» дужок, усередині яких стоїть `поз` (найглибших), чи None."""
    глибина = 0
    for і in range(поз - 1, max(-1, поз - 400), -1):
        с = текст[і]
        if с == ")":
            глибина += 1
        elif с == "(":
            if глибина == 0:
                return і
            глибина -= 1
        elif текст.startswith("\n\n", і):
            return None
    return None


def _закрита_дужка(текст, відкрита):
    """Позиція після «)», що закриває дужку на `відкрита`, чи None (у межах 400 знаків і абзацу)."""
    глибина = 0
    for і in range(відкрита, min(len(текст), відкрита + 400)):
        с = текст[і]
        if с == "(":
            глибина += 1
        elif с == ")":
            глибина -= 1
            if глибина == 0:
                return і + 1
        elif текст.startswith("\n\n", і):
            return None
    return None


def _дати_слова(хвіст):
    """Дати звороту «власник», що належать слову: дата, перед якою (від попередньої дати) нема слова виду —
    «(власник, розбір дошки 27.10)» дату бере розбір, «(власник 26.10; вимір 27.10)» — 26.10."""
    вихід, від = [], 0
    for д in _ДАТА_Р.finditer(хвіст):
        if not _ВИД.search(хвіст[від:д.start()]):
            вихід.append("%02d.%s" % (int(д.group(1)), д.group(2)))
        від = д.end()
    return вихід


def одиниці_тексту(текст):
    """Одиниці одного тексту: список dict(поч, кін, вид, дати). Поч/кін — позиції в `текст` (рядки збережено)."""
    вихід = []

    def зайнято(поз):
        return any(о["поч"] <= поз < о["кін"] for о in вихід)

    for з in _ВЛАСНИК.finditer(текст):
        if зайнято(з.start()):
            continue
        дужка = _відкрита_дужка(текст, з.start())
        кін = _закрита_дужка(текст, дужка) if дужка is not None else None
        кін = кін or _межа(текст, з.end())
        хвіст = текст[з.end():кін]
        перша = _ДАТА_Р.search(хвіст)
        if перша:
            між = хвіст[:перша.start()]
            if _ВЛАСНИК.search(між):
                continue  # дату бере ближчий «власник»
            if "(" in між:
                if not re.fullmatch(r"\s*\(\s*", між):
                    continue  # дата — своїх дужок далі в реченні (прохід дат нижче)
                кін = _закрита_дужка(текст, з.end() + між.index("(")) or кін
                хвіст = текст[з.end():кін]
            elif дужка is None and _ВИД.search(між):
                # «слову власника … → перепис 26.10»: дата — того виду, що стоїть між ними, не слова власника.
                вихід.append(dict(поч=з.start(), кін=кін, вид="інше", дати=_дати(хвіст)))
                continue
            зс = _ЗА_СЛОВОМ.search(текст[max(0, з.start() - 60):з.start()])
            поч = з.start() - min(60, з.start()) + зс.start() if зс else з.start()
            вихід.append(dict(поч=поч, кін=кін, вид="за-словом" if зс else "власник", дати=_дати_слова(хвіст)))
        elif з.group(1).lower() == "власник" and re.match(r"\s*\)", текст[з.end():з.end() + 3]) and (
                re.search(r"\(\s*$|—\s*$", текст[max(0, з.start() - 3):з.start()])):
            вихід.append(dict(поч=з.start(), кін=з.end() + текст[з.end():].index(")") + 1, вид="власник-б/д",
                              дати=[]))
        elif з.group(1).lower() == "власник" and re.search(r"—\s*$", текст[max(0, з.start() - 3):з.start()]) and \
                re.match(r"\s*(?:[.;,)]|$)", текст[з.end():з.end() + 2]):
            вихід.append(dict(поч=з.start(), кін=з.end(), вид="власник-б/д", дати=[]))
    for д in _ДАТА.finditer(текст):
        if зайнято(д.start()):
            continue
        дужка = _відкрита_дужка(текст, д.start())
        if дужка is None:
            continue
        мітка = текст[дужка + 1:д.start()]
        мітка = мітка[мітка.rfind(";") + 1:]  # зворот дати — частина дужок після останньої «;» перед нею
        if _ВЕРСІЯ.search(мітка) or _ВЛАСНИК.search(мітка):
            continue
        поч_звороту = д.start() - len(мітка)
        кін = _межа(текст, д.start())
        зворот = текст[поч_звороту:кін]
        вид = "інше" if (_ВИД.search(re.sub(r"«[^»]*»", "", мітка)) or _ФАЙЛ.search(зворот)) else "гола-дата"
        вихід.append(dict(поч=поч_звороту, кін=кін, вид=вид, дати=_дати(текст[д.start():кін])))
    вихід.sort(key=lambda о: о["поч"])
    # Ключ: усе речення одиниці (норма звороту стоїть і до посилання, і після нього: «(власник 26.10) межі часу …
    # нема»), а коли в реченні кілька одиниць — ще й її номер у ньому «⟨n⟩».
    за_реченням = {}
    for о in вихід:
        поч = _початок_речення(текст, о["поч"])
        кін = _кінець_речення(текст, о["кін"])
        о["речення"] = (поч, кін)
        за_реченням.setdefault((поч, кін), []).append(о)
        о["зворот"] = _нормувати(текст[о["поч"]:о["кін"]])
    for (поч, кін), група in за_реченням.items():
        речення = _нормувати(текст[поч:кін])
        for н, о in enumerate(група, 1):
            о["ключ"] = речення if len(група) == 1 else "%s ⟨%d⟩" % (речення, н)
    return вихід


def журнал_дат(корінь):
    """Дати ДД.ММ, на які журнал має запис: заголовок розділу «## …» чи штамп запису «- **ДД.ММ…**»."""
    дати = set()
    шлях = os.path.join(корінь, ЖУРНАЛ)
    if not os.path.exists(шлях):
        return дати
    for рядок in open(шлях, encoding="utf-8"):
        if рядок.startswith("## "):
            дати.update(_дати(рядок, рік=True))
        elif рядок.startswith("- "):
            штамп = re.match(r"- \*\*([^*]+)\*\*", рядок)
            дати.update(_дати(штамп.group(1) if штамп else рядок[:40], рік=True))
    return дати


def вердикти(корінь):
    """(файл, ключ) → dict вердикту з даних приладу."""
    шлях = os.path.join(корінь, ВЕРДИКТИ)
    вихід = {}
    if not os.path.exists(шлях):
        return вихід
    for н, рядок in enumerate(open(шлях, encoding="utf-8"), 1):
        рядок = рядок.rstrip("\n")
        if not рядок or рядок.startswith("#") or н == 1 and рядок.startswith("файл\t"):
            continue
        поля = рядок.split("\t")
        if len(поля) < 3:
            continue
        вихід[(поля[0], поля[1])] = dict(вердикт=поля[2].strip(), журнал=(поля[3:4] or [""])[0],
                                         звідки=(поля[4:5] or [""])[0])
    return вихід


def усі_одиниці(корінь):
    вихід, нема = [], []
    for ф in ОБСЯГ:
        шлях = os.path.join(корінь, ф)
        if not os.path.exists(шлях):
            нема.append(ф)
            continue
        текст = open(шлях, encoding="utf-8").read()
        бачено = {}
        for о in одиниці_тексту(текст):
            о["файл"] = ф
            о["рядок"] = текст.count("\n", 0, о["поч"]) + 1
            бачено[о["ключ"]] = бачено.get(о["ключ"], 0) + 1
            if бачено[о["ключ"]] > 1:  # той самий зворот удруге у файлі — окрема одиниця
                о["ключ"] += " #%d" % бачено[о["ключ"]]
            вихід.append(о)
    return вихід, нема


def оцінити(о, дані, дати_журналу):
    """→ (пункт | None, причина, вердикт)."""
    в = дані.get((о["файл"], о["ключ"]), {}).get("вердикт", "")
    вид = о["вид"]
    if в in ВЕРДИКТ_П1:  # суд бачить слово власника й за голою датою («Межі (18.10)»)
        return "п.1", "вердикт " + в, в
    if вид == "власник" and not в:
        return "п.1", "без вердикту", в
    if вид == "власник-б/д":
        return "п.2", "«власник» без дати", в
    if вид in ("власник", "за-словом"):
        без_запису = [д for д in о["дати"] if д not in дати_журналу]
        if без_запису:
            return "п.2", "дати нема в журналі: " + ",".join(без_запису), в
    if вид == "власник" and в in ВЕРДИКТ_П2:
        return "п.2", "вердикт " + в, в
    if вид == "гола-дата":
        return "п.3", "дата без виду джерела", в
    if вид == "власник" and в not in ВЕРДИКТ_НЕ:
        return "п.1", "вердикт «%s» поза словником" % в, в
    return None, "", в


def main(argv=None):
    п = argparse.ArgumentParser()
    п.add_argument("--корінь", default=КОРІНЬ)
    п.add_argument("--одиниці", action="store_true")
    п.add_argument("--самоперевірка", action="store_true")
    а = п.parse_args(argv)
    if а.самоперевірка:
        return самоперевірка()
    одиниці, нема = усі_одиниці(а.корінь)
    дані = вердикти(а.корінь)
    дати_журналу = журнал_дат(а.корінь)
    if а.одиниці:
        for о in одиниці:
            пункт, причина, в = оцінити(о, дані, дати_журналу)
            print("\t".join([о["вид"], "%s:%d" % (о["файл"], о["рядок"]), в or "—", пункт or "—", о["зворот"],
                             о["ключ"]]))
        return 0
    місця = []
    for о in одиниці:
        пункт, причина, в = оцінити(о, дані, дати_журналу)
        if пункт:
            місця.append((пункт, о, причина))
    for пункт, о, причина in місця:
        print("%s:%d · %s · %s · %s · речення: %s" % (о["файл"], о["рядок"], пункт, причина, о["зворот"][:120],
                                                     о["ключ"][:90]))
    види = {}
    for о in одиниці:
        види[о["вид"]] = види.get(о["вид"], 0) + 1
    print("одиниць %d: %s" % (len(одиниці), ", ".join("%s %d" % кв for кв in sorted(види.items()))))
    за_пунктом = {}
    for пункт, _, причина in місця:
        за_пунктом[пункт] = за_пунктом.get(пункт, 0) + 1
    без = sum(1 for _, _, причина in місця if причина == "без вердикту")
    print("за пунктами: %s; з них п.1 без вердикту %d" % (
        ", ".join("%s %d" % кв for кв in sorted(за_пунктом.items())) or "—", без))
    за_файлом = {}
    for _, о, _ in місця:
        за_файлом[о["файл"]] = за_файлом.get(о["файл"], 0) + 1
    print("за файлами: " + (", ".join("%s %d" % (ф, за_файлом[ф]) for ф in ОБСЯГ if ф in за_файлом) or "—"))
    ключі = {(о["файл"], о["ключ"]) for о in одиниці}
    зайві = sorted(к for к in дані if к not in ключі)
    print("вердиктів без одиниці (зворот змінено чи знято): %d" % len(зайві))
    if нема:
        print("файлів обсягу нема на дереві: " + ", ".join(нема))
    print("місць: %d" % len(місця))
    return 0


