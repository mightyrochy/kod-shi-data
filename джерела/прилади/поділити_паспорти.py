def чергується(старі, а, б):
    """Чи `старі` — точне чергування рядків `а` і `б` (кожен файл у своєму порядку).

    Динаміка за бітовою маскою: D_i — множина j (скільки рядків `а` уже взято після i рядків `старі`); крок із `а` —
    j → j+1, коли а[j] == рядок; крок із `б` — j лишається, коли б[i−j] == рядок. Жадібно було б хибним на повторах.
    """
    n, m, h = len(старі), len(а), len(б)
    if n != m + h:
        return False
    маска_а, маска_б = {}, {}
    for j, р in enumerate(а):
        маска_а[р] = маска_а.get(р, 0) | (1 << j)
    for k, р in enumerate(б):
        маска_б[р] = маска_б.get(р, 0) | (1 << (h - k))  # біт h−k: k = i−j → зсув (h−i) дає біт j
    D = 1
    for i, р in enumerate(старі):
        з_а = (D & маска_а.get(р, 0)) << 1
        qб = маска_б.get(р, 0)
        вирівняна = qб >> (h - i) if h >= i else qб << (i - h)
        з_б = D & вирівняна
        D = з_а | з_б
        if not D:
            return False
    return bool((D >> m) & 1)


def звірити_один(корінь, було, шапка, історія):
    """→ список вад (порожній — звірено)."""
    вади = []
    ш, і = рядки_файла(шапка), рядки_файла(історія)
    старі = рядки_файла(було)
    покажчик_рядок = покажчик(корінь)
    if і[:3] != преамбула_історії(корінь) or (len(і) > 3 and і[3] != ''):
        return [f'історія {корінь}: преамбула не та']
    і = і[4:]
    # Рядок-покажчик — єдине, чого не було в старому паспорті; порожній рядок перед ним міг бути доданий (а міг бути
    # паспортним) — звіряємо обидва прочитання, жадібності нема.
    if not ш or ш[-1] != покажчик_рядок:
        вади.append(f'шапка {корінь}: наприкінці нема рядка-покажчика на історію')
        ш = ш[:-1]
    else:
        ш = ш[:-1]
    if not (чергується(старі, ш, і) or (ш and ш[-1] == '' and чергується(старі, ш[:-1], і))):
        вади.append(f'{корінь}: рядки старого паспорта не складаються з шапки й історії в порядку старого')
    if рядки_приладу(було) != рядки_приладу(шапка) or any(рядок_приладу(р) for р in і):
        вади.append(f'{корінь}: рядки прилад:/база: шапки не ті, що в старому паспорті, чи є в історії')
    if розібрати_паспорт(було) != розібрати_паспорт(шапка):
        вади.append(f'{корінь}: розібрати_паспорт (прилад, аргументи, бази, помилки) шапки не той, що в старого')
    if не_паспорт(історія):
        вади.append(f'історія {корінь}: перший рядок має бути «# Історія кореня …», не «# Корінь …»')
    return вади


def не_паспорт(історія):
    return not історія.startswith(ЗАГОЛОВОК_ІСТОРІЇ)


def git_показати(реф, шлях):
    р = subprocess.run(['git', '-c', 'core.quotepath=off', 'show', f'{реф}:{шлях}'], cwd=КОРІНЬ, capture_output=True,
                       encoding='utf-8')
    return р.stdout if р.returncode == 0 else None


def з_бази(реф):
    """Паспорти бази: {корінь: текст}, лише з першим рядком «# Корінь …»."""
    вивід = subprocess.run(['git', '-c', 'core.quotepath=off', 'ls-tree', '--name-only', реф, 'аудит/корені/'],
                           cwd=КОРІНЬ, capture_output=True, encoding='utf-8', check=True).stdout.split('\n')
    результат = {}
    for шлях in вивід:
        if шлях.endswith('.md') and '/' in шлях:
            текст = git_показати(реф, шлях)
            if текст and текст.startswith(ШАПКА_ПАСПОРТА):
                результат[шлях.rsplit('/', 1)[-1][:-3]] = текст
    return результат


def читати(шлях):
    with open(шлях, encoding='utf-8') as ф:
        return ф.read()


def звірити_все(реф):
    базові = з_бази(реф)
    вади, перевірено, лише_шапка = [], 0, 0
    for корінь, було in sorted(базові.items()):
        шапка = читати(os.path.join(ТЕКА, корінь + '.md'))
        шлях = шлях_історії(корінь)
        if not os.path.isfile(шлях):
            if шапка != було:
                вади.append(f'{корінь}: паспорт змінено, а історії нема')
            else:
                лише_шапка += 1
                перевірено += 1
            continue
        вади += звірити_один(корінь, було, шапка, читати(шлях))
        перевірено += 1
    for ф in os.listdir(os.path.join(ТЕКА, ІСТОРІЯ)) if os.path.isdir(os.path.join(ТЕКА, ІСТОРІЯ)) else []:
        if ф[:-3] not in базові:
            вади.append(f'історія {ф}: у базі нема такого паспорта')
    return перевірено, лише_шапка, вади


def мірило(реф):
    базові = з_бази(реф)
    до = {к: рядки_файла(т) for к, т in базові.items()}
    після = {к: рядки_файла(читати(os.path.join(ТЕКА, к + '.md'))) for к in до}
    історії = {к: рядки_файла(читати(шлях_історії(к))) for к in до if os.path.isfile(шлях_історії(к))}
    рядки = [f'паспортів (перший рядок «# Корінь …»): {len(до)}',
             f'рядків у паспортах разом: {sum(map(len, до.values()))} → {sum(map(len, після.values()))} '
             f'(+ {sum(map(len, історії.values()))} у файлах історії; усього {sum(map(len, після.values())) + sum(map(len, історії.values()))})',
             f'найбільший паспорт: {max(map(len, до.values()))} → {max(map(len, після.values()))}',
             f'паспортів понад {ДОВГИЙ_ПАСПОРТ} рядків: {sum(1 for в in до.values() if len(в) > ДОВГИЙ_ПАСПОРТ)} → '
             f'{sum(1 for в in після.values() if len(в) > ДОВГИЙ_ПАСПОРТ)}',
             f'файлів історії: {len(історії)}']
    for к, в in sorted(після.items(), key=lambda x: -len(x[1])):
        if len(в) > ДОВГИЙ_ПАСПОРТ:
            розділи = [(len(т), з) for р, з, т in блоки(в) if р == 2]
            найбільший = max(розділи) if розділи else (0, '')
            рядки.append(f'  лишився довшим: {к} — {len(до[к])} → {len(в)}; найбільший розділ шапки: '
                         f'«{найбільший[1][:70]}» — {найбільший[0]} рядків')
    return рядки


def головна():
    а = sys.argv[1:]
    реф = а[а.index('--база') + 1] if '--база' in а else 'origin/main'
    if '--звірити' in а:
        перевірено, лише_шапка, вади = звірити_все(реф)
        print(f'звірено {перевірено} з {len(з_бази(реф))} паспортів бази ({лише_шапка} без поділу — лишились як були); '
              f'вад {len(вади)}')
        for в in вади:
            print('ПОМИЛКА ' + в, file=sys.stderr)
        return 1 if вади else 0
    if '--мірило' in а:
        print('\n'.join(мірило(реф)))
        return 0
    підсумок = поділити_все()
    for корінь, було, шапка, історія in підсумок:
        print(f'{корінь}: {було} → шапка {шапка} + історія {історія}')
