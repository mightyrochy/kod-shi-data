# -*- coding: utf-8 -*-
"""ПОДІЛ ПАСПОРТІВ: шапка лишається в `аудит/корені/<корінь>.md`, датовані кроки й дослідження — дослівно у файлі
історії `аудит/корені/історія/<корінь>.md` (наряд «Паспорт-шапка-й-історія», диспетчер 20.11, за планом К9: Г2, Д13).

ЧОМУ. Паспорт читає кожен виконавець кроку й кожна перевірка, а корисні в ньому перші півсотні рядків: решта — щоденник
кроків, який доточував CI з файлів `аудит/корені/<корінь>.d/**`. Скрипт ділить наявні паспорти раз, далі історію
доточує `згорнути_паспорти.py`.

ДЕ ЛЕЖИТЬ ІСТОРІЯ. `аудит/корені/історія/<корінь>.md` — теку читачі паспортів не бачать самою будовою: храповик читає
лише `*.md` безпосередньо в `аудит/корені/`, згортання дошки (`корені_паспортів`) — так само, і перший рядок історії —
«# Історія кореня …», не «# Корінь …». Винятків у читачах нема.

ЩО ЛИШАЄТЬСЯ В ШАПЦІ. Паспортом вважається `аудит/корені/*.md`, чий перший рядок «# Корінь …» (переліки й вибірки —
не паспорти). Паспорт ділиться на блоки за рядками заголовків (`## …`, `### …`):
  1. усе до першого заголовка з датою (`ДД.ММ`, `ДД.ММ.РРРР`, `РРРР-ММ-ДД`) — шапка;
  2. далі кожен блок іде в історію, КРІМ: блока без дати в заголовку, чия назва — з переліку шапки (`Що лишилось`,
     `Стан і що лишилось`, `Прилад і число`, `Невдалі підходи…`, `Питання менеджерові`, `Клас місць`, `Проблема`,
     `Рішення`, `Інваріант…`, `Напрямок…`, `Живе мірило`, `Мірило`) з його підблоками без дати; і розділів
     «Рішення менеджера ДД.ММ» від 19.11 й новіших — разом з усіма підблоками (рішення менеджера 19.11 і новіші —
     шапка за нарядом); і будь-якого блока, де стоїть рядок `прилад:`/`база:` чи схожий на нього (їх читає храповик
     кореня, вони лишаються в паспорті; частина історії без них);
  3. підблок із датою в заголовку під блоком шапки — історія.
Порядок рядків в обох файлах — як у старому паспорті; рядок історії дослівно ті самі рядки, жодного не змінено. До
шапки дописується один рядок-покажчик на історію; історія починається власним заголовком і коментарем (3 рядки).

ЗВІРКА (`--звірити`): окремо від поділу, з гілки `main` (`--база <реф>`) чи з аргументів `--було <файл> --шапка <файл>
--історія <файл>`: кожен рядок старого паспорта — або в шапці, або в історії того самого кореня, кожен файл у порядку
старого (поділ рядків між файлами точний, без жадібного вгадування — динамічне програмування за бітовою маскою); рядки
`прилад:`/`база:` у шапці ті самі, в історії їх нема.

ЗАПУСК (з кореня репозиторію):
    python3 джерела/прилади/поділити_паспорти.py                       # поділити паспорти в робочому дереві
    python3 джерела/прилади/поділити_паспорти.py --звірити --база origin/main   # звірити робоче дерево з базою
    python3 джерела/прилади/поділити_паспорти.py --мірило --база origin/main    # ДО → ПІСЛЯ для PR
Паспорт, чия історія вже є, пропускається (повторний запуск нічого не міняє).
"""
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from храповик_кореня import розібрати_паспорт, рядки_приладу, ПРИЛАД, БАЗА, схожий

КОРІНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ТЕКА = os.path.join(КОРІНЬ, 'аудит', 'корені')
ІСТОРІЯ = 'історія'
ШАПКА_ПАСПОРТА = '# Корінь '
ЗАГОЛОВОК_ІСТОРІЇ = '# Історія кореня '
ДОВГИЙ_ПАСПОРТ = 150

ЗАГОЛОВОК = re.compile(r'^(#{2,6}) ')
ДАТА_КРАПКА = re.compile(r'(?<!\d)(\d{1,2})\.(\d{2})(?!\d)')
ДАТА_ISO = re.compile(r'(?<!\d)(\d{4})-(\d{2})-(\d{2})(?!\d)')
РІШЕННЯ_МЕНЕДЖЕРА = re.compile(r'^#{2,6} Рішення менеджера (\d{1,2})\.(\d{2})')
ІМЕНА_ШАПКИ = re.compile(
    r'^#{2,6} (Що лишилось|Стан і що лишилось|Прилад і число|Невдалі підходи|Питання менеджерові|Питання до рішення'
    r'|Клас місць|Проблема|Рішення|Інваріант|Напрямок|Живе мірило|Мірило)(?![\w-])')


def має_дату(заголовок):
    return bool(ДАТА_КРАПКА.search(заголовок) or ДАТА_ISO.search(заголовок))


def нове_рішення(заголовок):
    """«Рішення менеджера ДД.ММ …» від 19.11 й новіше (рік не пишуть — усі розділи 2026)."""
    м = РІШЕННЯ_МЕНЕДЖЕРА.match(заголовок)
    return bool(м) and (int(м.group(2)), int(м.group(1))) >= (11, 19)


def рядок_приладу(рядок):
    return bool(ПРИЛАД.match(рядок) or БАЗА.match(рядок) or схожий(рядок))


def блоки(рядки):
    """Рядки → [(рівень, заголовок, [рядки блока])]; перший блок — усе до першого `##` (рівень 1)."""
    результат, поточний = [], (1, '', [])
    for р in рядки:
        м = ЗАГОЛОВОК.match(р)
        if м:
            результат.append(поточний)
            поточний = (len(м.group(1)), р, [р])
        else:
            поточний[2].append(р)
    результат.append(поточний)
    return результат


def ділити(рядки):
    """→ (рядки шапки, рядки історії); вхід — рядки старого паспорта без `\\n`."""
    список = блоки(рядки)
    межа = next((i for i, (р, з, _) in enumerate(список) if р > 1 and має_дату(з)), None)
    шапка, історія, стек = [], [], []  # стек: (рівень, куди, нове рішення)
    for i, (рівень, заголовок, текст) in enumerate(список):
        while стек and стек[-1][0] >= рівень:
            стек.pop()
        батько = стек[-1] if стек and стек[-1][0] > 1 else None
        нове = False
        if рівень == 1 or межа is None or i < межа:
            куди = 'ш'
        elif батько and батько[2]:
            куди, нове = 'ш', True  # підблок нового рішення менеджера
        elif нове_рішення(заголовок):
            куди, нове = 'ш', True
        elif батько:
            # Підблок блока шапки: з датою — історія, без — шапка; підблок блока історії — історія.
            куди = 'і' if батько[1] == 'і' or має_дату(заголовок) else 'ш'
        else:
            куди = 'ш' if ІМЕНА_ШАПКИ.match(заголовок) and not має_дату(заголовок) else 'і'
        if куди == 'і' and any(рядок_приладу(р) for р in текст):
            куди = 'ш'
        стек.append((рівень, куди, нове))
        (шапка if куди == 'ш' else історія).extend(текст)
    return шапка, історія


def покажчик(корінь):
    return (f'Кроки й дослідження цього кореня — `аудит/корені/{ІСТОРІЯ}/{корінь}.md` (файли кроків `.d/` CI згортає '
            f'туди, а не сюди; «Що лишилось» шапки замінюється блоком `<<<< замінити`).')


def преамбула_історії(корінь):
    return [f'{ЗАГОЛОВОК_ІСТОРІЇ}{корінь}: кроки й дослідження', '',
            f'<!-- Датовані кроки й дослідження паспорта `аудит/корені/{корінь}.md` дослівно, у порядку паспорта. -->']


def шлях_історії(корінь):
    return os.path.join(ТЕКА, ІСТОРІЯ, корінь + '.md')


def паспорти_тека():
    """Імена паспортів у теці: `*.md`, перший рядок «# Корінь …»."""
    імена = []
    for ф in sorted(os.listdir(ТЕКА)):
        шлях = os.path.join(ТЕКА, ф)
        if ф.endswith('.md') and os.path.isfile(шлях):
            with open(шлях, encoding='utf-8') as файл:
                if файл.readline().startswith(ШАПКА_ПАСПОРТА):
                    імена.append(ф[:-3])
    return імена


def рядки_файла(текст):
    """Текст → рядки без `\\n`; кінцевий `\\n` — не окремий рядок (запис у файл додасть його назад)."""
    р = текст.split('\n')
    if р and р[-1] == '':
        р.pop()
    return р


def записати(шлях, рядки):
    os.makedirs(os.path.dirname(шлях), exist_ok=True)
    with open(шлях, 'w', encoding='utf-8') as ф:
        ф.write('\n'.join(рядки) + '\n')


def поділити_один(корінь):
    шлях = os.path.join(ТЕКА, корінь + '.md')
    with open(шлях, encoding='utf-8') as ф:
        рядки = рядки_файла(ф.read())
    шапка, історія = ділити(рядки)
    if not історія:
        return None
    if шапка[-1] != '':
        шапка.append('')  # рядок-покажчик відокремлено порожнім; порожні рядки паспорта не відкидаємо
    шапка.append(покажчик(корінь))
    записати(шлях_історії(корінь), преамбула_історії(корінь) + [''] + історія)
    записати(шлях, шапка)
    return len(рядки), len(шапка), len(історія)


def поділити_все():
    підсумок = []
    for корінь in паспорти_тека():
        if os.path.isfile(шлях_історії(корінь)):
            continue
        р = поділити_один(корінь)
        if р:
            підсумок.append((корінь, *р))
    return підсумок


