# -*- coding: utf-8 -*-
"""Спільна схема дошки для перевірки фрагментів і тижневого зрізу.

Метадані — один компактний блок у клітинці, після прози:
<!-- дошка: дата=2026-10-26; рід=видима; попередник=тема 123; механізм=копія-поняття -->
Новий рядок тримає цей блок ПОЗА статусом: «стан N:» не стирає дату появи.
Закриття (також ЧАСТКОВО) додає в клітинку статусу:
<!-- дошка: механізм=копія-поняття; закриття=корінь; доказ=проба; дата-закриття=2026-10-26 -->
«виявлено: проба» позначає автоматичну знахідку; решта джерел — як у AGENTS.md.

Механізми звужено до повторюваних категорій розмітки; рідкісні вільні пояснення
й «локальна» лишаються «інше». Мапа до ГП — аналітичне групування, а не доказ
усунення причини. Кілька механізмів через «+»; рядок рахується раз у кожній ГП.
"""
import re
from datetime import date

МЕХАНІЗМИ = {
    'мірило-не-те': 'ГП-1', 'нема-мірила': 'ГП-1', 'вимір-хибний': 'ГП-1',
    'інструкція-моделі': 'ГП-2', 'форма-виходу-моделі': 'ГП-2',
    'код-читає-слова': 'ГП-2', 'код-пише-слова': 'ГП-2', 'латка': 'ГП-2',
    'правило-без-входу': 'ГП-3', 'модель-вигадує': 'ГП-3',
    'копія-поняття': 'ГП-4', 'запис-без-читача': 'ГП-4', 'неповна-правка': 'ГП-4',
    'регресія': 'ГП-4', 'межа-неясна': 'ГП-4', 'чуже-поле': 'ГП-4',
    'дані-неповні': 'ГП-5', 'інше': 'не визначено',
}
ЗАКРИТТЯ = ('корінь', 'симптом')
ДОКАЗИ = ('живий', 'проба', 'документ', 'нема')
РОДИ = ('видима', 'внутрішня', 'дані', 'мірило', 'процес', 'рішення', 'вимір', 'вимога')
ДЖЕРЕЛА = ('перевірка', 'живий', 'тестувальниця', 'власник', 'менеджер', 'виконавець', 'проба')
# Номери, видані до нового формату, і їхні закриття приймаються без нових полів.
# Новий формат обов'язковий у перевірці PR від цього номера (AGENTS.md, п.13).
ПЕРШИЙ_СУВОРИЙ_НОМЕР = 10176
ПОПЕРЕДНИК = re.compile(r'(?:ні|тема [1-9]\d*|повернення закритого [1-9]\d*|регресія #[1-9]\d* [1-9]\d*)')
БЛОК = re.compile(r'<!-- дошка:\s*(.*?)\s*-->')
ВИЯВЛЕНО = re.compile(r'(?:^|[;·|]\s*)виявлено:\s*([^;|]+)')


def метадані(текст):
    """Читає лише явні блоки, не слова з опису вади. Не ховає описок і дублів."""
    поля = {}
    for блок in БЛОК.findall(текст):
        бачені = set()
        for пара in блок.split(';'):
            ключ, роздільник, значення = пара.strip().partition('=')
            if not роздільник or not значення.strip():
                raise ValueError(f'поле {ключ or "дошка"}: очікується назва=значення')
            if ключ in бачені or (ключ in поля and поля[ключ] != значення.strip()):
                raise ValueError(f'поле {ключ}: повторено з неоднозначним значенням')
            бачені.add(ключ)
            поля[ключ] = значення.strip()
    дозволені = {'дата', 'рід', 'попередник', 'механізм', 'закриття', 'доказ', 'дата-закриття'}
    for ключ in поля.keys() - дозволені:
        raise ValueError(f'поле {ключ}: невідоме')
    return поля


def механізми(значення):
    return значення.split('+')


def групи(значення):
    return {МЕХАНІЗМИ[м] for м in механізми(значення)}


def перевірити_поля(текст, новий=False, закрито=False, дата_появи=''):
    """Перевіряє поля блоку й хронологію проти дати появи з решти рядка чи дошки."""
    try:
        поля = метадані(текст)
    except ValueError as помилка:
        return [str(помилка)]
    обовязкові = ({'дата', 'рід', 'попередник', 'механізм'} if новий else set())
    if закрито:
        обовязкові |= {'механізм', 'закриття', 'доказ', 'дата-закриття'}
    помилки = [f'поле {к}: відсутнє' for к in sorted(обовязкові - поля.keys())]
    переліки = {'рід': РОДИ, 'закриття': ЗАКРИТТЯ, 'доказ': ДОКАЗИ}
    for ключ, значення in поля.items():
        if ключ in переліки and значення not in переліки[ключ]:
            помилки.append(f'поле {ключ}: очікується {", ".join(переліки[ключ])}')
        elif ключ in ('дата', 'дата-закриття'):
            try:
                if date.fromisoformat(значення).isoformat() != значення:
                    raise ValueError
            except ValueError:
                помилки.append(f'поле {ключ}: очікується справжня дата РРРР-ММ-ДД')
        elif ключ == 'попередник' and not ПОПЕРЕДНИК.fullmatch(значення):
            помилки.append('поле попередник: ні / тема N / повернення закритого N / регресія #PR N')
        elif ключ == 'механізм' and any(м not in МЕХАНІЗМИ for м in механізми(значення)):
            помилки.append(f'поле механізм: очікується перелік із {", ".join(МЕХАНІЗМИ)}')
    if новий:
        джерело = ВИЯВЛЕНО.search(текст)
        if not джерело or джерело[1].strip() not in ДЖЕРЕЛА:
            помилки.append(f'поле виявлено: очікується {", ".join(ДЖЕРЕЛА)}')
    if max(дата_появи, поля.get('дата', '')) > поля.get('дата-закриття', '9999-12-31'):
        помилки.append('поле дата-закриття: передує даті появи')
    return помилки
