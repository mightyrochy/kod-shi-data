def файли_продукту(корінь, розширення):
    """Усі файли коду продукту з даним розширенням: `джерела/` і `zhnyvarka/` на будь-якій глибині, крім проб і приладів
    (`джерела/проби/`, `джерела/прилади/`) і стороннього (`node_modules`, `__pycache__`, теки з крапки). Одне правило для
    Python і JS, без переліку тек і без відбору за назвою файлу. → [(шлях від кореня з «/», абсолютний шлях)], за шляхом."""
    вих = []
    for коріння in КОРЕНІ_ПРОДУКТУ:
        для_обходу = os.path.join(корінь, коріння)
        for тека, теки, назви in os.walk(для_обходу):
            відносна = os.path.relpath(тека, корінь).replace(os.sep, "/")
            теки[:] = sorted(т for т in теки
                             if т not in СТОРОННЄ and not т.startswith(".") and (відносна + "/" + т) not in ПОЗА_КЛАСОМ)
            for ім_ф in назви:
                if ім_ф.endswith(розширення):
                    вих.append((відносна + "/" + ім_ф, os.path.join(тека, ім_ф)))
    return sorted(вих)


def файли_показу(корінь):
    """Код JS продукту: (шлях, код без коментарів, значення рядків)."""
    вих = []
    for ім_ф, шлях in файли_продукту(корінь, ".js"):
        with open(шлях, encoding="utf-8") as ф:
            код, значення = очистити(ф.read())
        вих.append((ім_ф, код, значення))
    return вих


def функція_рядка(функції, рядок):
    """Імʼя й код функції верхнього рівня, що містить рядок (1-базовий); нема — ("(верх)", "")."""
    ім, тіло = "(верх)", ""
    for н, п, т in функції:
        if п <= рядок < п + т.count("\n") + 1:
            ім, тіло = н, т
    return ім, тіло


def дії_вікна(код):
    """Що робить КОД однієї функції щодо вікна (за синтаксисом, не за словами): умова `if/while (…)`, у якій порівняння
    `<`, `<=`, `>`, `>=` зіставляє ідентифікатор токенів з ідентифікатором вікна; читання поля вікна рушія як
    ідентифікатор поза рядками й коментарями; скорочення масиву викликом `splice/pop/shift` чи `.length =`.
    → (порівняння, поле, скорочення) — булеві."""
    порівняння = False
    for м in re.finditer(r"(?<![\w$])(?:if|while)\s*\(", код):
        відкрита = м.end() - 1
        умова = код[відкрита + 1:дужка(код, відкрита)]
        if (re.search(r"(?<![=<>!-])(?:<=|>=|<|>)(?![=>])", умова) and ТОКЕН.search(умова) and ВІКНО.search(умова)
                and not re.search(r"(?<![\w$])(?:console|log)\b", умова)):
            порівняння = True
    поле = bool(ПОЛЯ_РУШІЯ.search(код))
    скорочення = bool(re.search(r"\.\s*(?:splice|pop|shift)\s*\(|\.length\s*=(?!=)", код))
    return порівняння, поле, скорочення


def лійка_і_функції(файли):
    """→ (функції конуса лійки [імена], {ім: код}, {ім: файл}). Конус — ворота й те, що вони кличуть у два кроки."""
    функції, файл_функції = {}, {}
    for ім_ф, код, _ in файли:
        for ім, _, тіло in М.функції_js(код):
            функції[ім] = тіло
            файл_функції[ім] = ім_ф
    # лійка — самі ворота й те, що вони кличуть у два кроки (черга, планувальник, вміщення запиту, дзвінок); глибше
    # лежить увесь показ, і зайвий рядок про «токен» і «контекст» там не знає про вікно
    в_конусі, черга = set(), [(в, 0) for в in ВОРОТА if в in функції]
    while черга:
        ім, глиб = черга.pop(0)
        if ім in в_конусі:
            continue
        в_конусі.add(ім)
        if глиб < ГЛИБИНА_ЛІЙКИ:
            for інше in sorted(функції):
                if інше not in в_конусі and re.search(r"(?<!%s)%s(?!%s)" % (БУКВА, re.escape(інше), БУКВА), функції[ім]):
                    черга.append((інше, глиб + 1))
    return sorted(в_конусі), функції, файл_функції


def факти_лійки(корінь):
    """Що в КОДІ конуса лійки знає про вікно: функція, де є і порівняння токенів із вікном, і читання поля вікна рушія,
    і скорочення, — точка (паспорт: «одна точка знає вікно»); п.1, п.2, п.3 закриваються її наявністю по частинах."""
    файли = файли_показу(корінь)
    імена, функції, _ = лійка_і_функції(файли)
    дії = {ім: дії_вікна(функції[ім]) for ім in імена}
    м_стеля = re.search(r"const\s+СТЕЛЯ_ЗАПИТУ_П\s*=\s*(\d+)", "\n".join(к for _, к, _ in файли))
    літерали = []
    for ім_ф, код, _ in файли:
        for м in re.finditer(r'\b(?:const|let)\s+(' + ІД + r')\s*=\s*([\d_]+)\s*;', код):
            н = код.count('\n', 0, м.start()) + 1
            власник, _ = функція_рядка(М.функції_js(код), н)
            if ВІКНО.search(м[1]) and власник in імена:
                літерали.append('%s:%d · %s=%s' % (ім_ф, код.count('\n', 0, м.start()) + 1, м[1], м[2]))
    точки = [ім for ім in імена if all(дії[ім])]
    return dict(функції_конуса=імена, порівняння=sorted(і for і in імена if дії[і][0]),
                поле_рушія=sorted(і for і in імена if дії[і][1]), точки=точки,
                стеля_символів=int(м_стеля.group(1)) if м_стеля else None, літерали_вікна=літерали,
                дії_лійки=(any(дії[і][0] for і in імена),
                           any(дії[і][1] for і in імена), any(дії[і][2] for і in імена)))


def залежності(граф, початок):
    """Замикання залежностей значення; цикли присвоєнь обходяться один раз."""
    бачені, черга = set(), list(початок)
    while черга:
        ім = черга.pop()
        if ім not in бачені:
            бачені.add(ім)
            черга.extend(граф.get(ім, ()))
    return бачені


def власне_правило_js(тіло, аргумент, функції):
    """Шукає скорочення даних аргументу під умовою вікна, включно з викликаними помічниками.

    Граф присвоєнь спрямований: зміна джерела міняє промпт; зміна лічильника, обчисленого з промпту, — ні.
    Лійка не входить у цей граф: передані їй дані самі по собі ще не мають правила скорочення.
    """
    граф, частини, черга, бачені = {}, [], [тіло], set()
    while черга:
        код = черга.pop()
        if код in бачені:
            continue
        бачені.add(код)
        частини.append(код)
        for м in re.finditer(r"(?<![\w$.])(" + ІД + r")(?:\s*\[[^;\n]*?\]|\." + ІД + r")*\s*=(?!=|>)\s*([^;\n]+)", код):
            граф.setdefault(м[1], set()).update(re.findall(ІД, м[2]))
        for м in re.finditer(r"(?<![\w$.])(" + ІД + r")\s*\(", код):
            ім = м[1]
            if ім in ВОРОТА or ім not in функції or re.search(r'\bfunction\s*$', код[:м.start()]):
                continue
            помічник = функції[ім]
            параметри = re.search(r"function\s+" + re.escape(ім) + r"\s*\(([^)]*)\)", помічник)
            if параметри:
                for п, а in zip(параметри[1].split(','), аргументи(код, код, м.end() - 1)):
                    п = п.strip()
                    for зм in re.findall(ІД, а):
                        граф.setdefault(зм, set()).add(п)
            черга.append(помічник)
    дані = залежності(граф, re.findall(ІД, аргумент))
    for код in частини:
        for м in re.finditer(r"(?<![\w$])(?:if|while)\s*\(", код):
            кінець = дужка(код, м.end() - 1)
            умова = код[м.end():кінець]
            if not (ТОКЕН.search(умова) and ВІКНО.search(умова) and re.search(r"[<>]", умова)):
                continue
            з = кінець + 1
            while з < len(код) and код[з].isspace():
                з += 1
            к = дужка(код, з) if код[з:з + 1] == '{' else код.find(';', з)
            дія = код[з:к]
            for скор in re.finditer(r"(" + ІД + r")\s*\.\s*(?:pop|shift|splice)\s*\(", дія):
                if скор[1] in дані:
                    return True
    return False


def сталі_бюджету_js(тіло, функції, файли):
    """Числові бюджети токенів, доступні зі складання цього запиту; назви й числа не задано переліком."""
    досяжні = set(re.findall(ІД, тіло))
    # Об'єкт налаштування має йти далі цілим: читання лише його сценарію чи фото бюджету не переносить.
    for м in re.finditer(r"\b(?:const|let)\s+(" + ІД + r")\s*=\s*(?:await\s+)?(" + ІД + r")\s*\(", тіло):
        змінна, постачальник = м[1], м[2]
        якщо_цілим = re.search(r"(?<![\w$.])" + re.escape(змінна) + r"(?![\w$]|\s*[.\[])", тіло[м.end():])
        if якщо_цілим and постачальник in функції and постачальник not in ВОРОТА:
            досяжні.update(re.findall(ІД, функції[постачальник]))
    вих = []
    for файл, код, _ in файли:
        for м in re.finditer(r"\bconst\s+(" + ІД + r")\s*=\s*([\d_]+)\s*;", код):
            if м[1] in досяжні and БЮДЖЕТ.search(м[1]):
                вих.append('%s:%d · %s=%s' % (файл, код.count('\n', 0, м.start()) + 1, м[1], м[2]))
    return вих


def порушення(змінний, арг0, ф, дії_своєї=None, своє_правило=False, сталі=()):
    """(пункти, чому) місця: за точкою лійки (`ф`) або за діями власної функції місця (`дії_своєї`, прямий транспорт)."""
    пункти, чому = [], []
    if not змінний:
        return пункти, чому
    if дії_своєї is None:
        є_порівняння, є_поле, є_скорочення = ф["дії_лійки"]
        де = "у конусі лійки (%d функцій)" % len(ф["функції_конуса"])
    else:
        є_порівняння, є_поле, є_скорочення = дії_своєї
        де = "у власній функції місця, повз лійку"
    if not є_порівняння:
        пункти.append(1)
        чому.append("%s токени не зіставлено з вікном умовою `if/while`: вхід міряє `вмістити_запит_П` символами "
                    "(стеля %s симв.)" % (де, ф["стеля_символів"]))
    сталі = tuple(сталі) + tuple(ф['літерали_вікна'] if дії_своєї is None else ())
    if not є_поле or сталі:
        пункти.append(2)
        чому.append("бюджет зі сталої: " + ", ".join(сталі) if сталі else
                    "поле вікна налаштування рушія %s не читається" % де)
    зріз = bool(арг0 and ЗРІЗ_СИМВОЛІВ.search(арг0))
    if not (є_порівняння and своє_правило) or зріз:
        пункти.append(3)
        чому.append("промпт, що не влазить, " + ("обрізається символами у виклику" if зріз else
                    "не має правила скорочення для даних самого виклику; лійка й скорочення сторонніх даних не закривають п.3"))
    return sorted(set(пункти)), чому


def місця(корінь):
    """→ (місця, факти лійки). Місце — виклик воріт (`модельП`, `модельП_блоки`) чи прямий транспорт до моделі
    (`fetch`/`XMLHttpRequest`/`sendBeacon`, чиї аргументи несуть запит: `messages`, `max_tokens`, `role:`, адресу
    лійки чи API) поза функціями конуса лійки — за класом, а не за назвою."""
    ф = факти_лійки(корінь)
    файли = файли_показу(корінь)
    всі_функції = {ім: тіло for _, код, _ in файли for ім, _, тіло in М.функції_js(код)}
    в_конусі = set(ф["функції_конуса"])
    вих = []
    for ім_ф, код, значення in файли:
        функції = М.функції_js(код)
        for м in re.finditer(r"(?<![\w$.`])(?<!function )(?<!function  )(модельП_блоки|модельП)\s*\(", код):
            рядок = код.count("\n", 0, м.start()) + 1
            ім, тіло = функція_рядка(функції, рядок)
            if ім in ВОРОТА:
                continue
            арг = аргументи(код, значення, м.end() - 1)
            змін, чому_змін = змінність_шлюзу(м.group(1), арг)
            # Лише код до виклику: скорочення після відповіді не захищає запит.
            початок = код.rfind(тіло, 0, м.start() + len(тіло))
            до_виклику = тіло[:м.start() - початок] if початок >= 0 else тіло
            власне = власне_правило_js(до_виклику, ','.join(арг[:3]), всі_функції)
            сталі = сталі_бюджету_js(тіло, всі_функції, файли)
            пункти, чому = порушення(змін, арг[0] if арг else "", ф, своє_правило=власне, сталі=сталі)
            вих.append(dict(файл=ім_ф, рядок=рядок, функція=ім, змінний=змін, змінність=чому_змін, пункти=пункти, чому=чому,
                            виклик_рядок=код.split("\n")[рядок - 1], виклик=м.group(1), шлях="лійка"))
        for м in re.finditer(r"(?<![\w$.])(?:fetch|XMLHttpRequest|sendBeacon|WebSocket)\s*\(", код):
            рядок = код.count("\n", 0, м.start()) + 1
            ім, тіло = функція_рядка(функції, рядок)
            if ім in в_конусі:
                continue
            арг = " ".join(аргументи(код, значення, м.end() - 1))
            if not ТРАНСПОРТ_МОДЕЛІ.search(арг):
                continue
            до_виклику = код[:м.start()] if ім == '(верх)' else тіло.split(м.group(0), 1)[0]
            власне = власне_правило_js(до_виклику, арг, всі_функції)
            сталі = сталі_бюджету_js(до_виклику, всі_функції, файли)
            пункти, чому = порушення(True, "", ф, дії_вікна(тіло), власне, сталі)
            вих.append(dict(файл=ім_ф, рядок=рядок, функція=ім, змінний=True, змінність="прямий транспорт до моделі повз лійку",
                            пункти=пункти, чому=чому, виклик_рядок=код.split("\n")[рядок - 1], виклик="транспорт", шлях="повз"))
    вих += місця_python(корінь, ф)
    вих.sort(key=lambda x: (x["файл"], x["рядок"]))
    return вих, ф


def python_дії(функції, ім):
    """Дії щодо вікна у функції `ім` модуля й тих, що вона кличе в цьому ж модулі (два кроки), за AST: умова
    `if/while/?:` з порівнянням `<`, `<=`, `>`, `>=`, де є ідентифікатор токенів і вікна; поле вікна рушія
    (рядковий ключ чи ідентифікатор); скорочення (`.pop/.remove/.splice`, `del`, присвоєння зрізу).
    → (порівняння, поле, скорочення)."""
    конус, черга = set(), [(ім, 0)]
    while черга:
        н, г = черга.pop(0)
        if н in конус or н not in функції:
            continue
        конус.add(н)
        if г < ГЛИБИНА_ЛІЙКИ:
            for в in ast.walk(функції[н]):
                if isinstance(в, ast.Call) and isinstance(в.func, ast.Name):
                    черга.append((в.func.id, г + 1))
    порівняння = поле = скорочення = False
    for н in sorted(конус):
        for в in ast.walk(функції[н]):
            if isinstance(в, (ast.If, ast.While, ast.IfExp)):
                for к in ast.walk(в.test):
                    if isinstance(к, ast.Compare) and any(isinstance(о, (ast.Lt, ast.LtE, ast.Gt, ast.GtE)) for о in к.ops):
                        імена = [ч.id for ч in ast.walk(к) if isinstance(ч, ast.Name)] + [ч.attr for ч in ast.walk(к) if isinstance(ч, ast.Attribute)]
                        if any(ТОКЕН.search(і) for і in імена) and any(ВІКНО.search(і) for і in імена):
                            порівняння = True
            if (isinstance(в, ast.Constant) and isinstance(в.value, str) and ПОЛЯ_РУШІЯ.fullmatch(в.value)) \
                    or (isinstance(в, ast.Name) and ПОЛЯ_РУШІЯ.fullmatch(в.id)) \
                    or (isinstance(в, ast.Attribute) and ПОЛЯ_РУШІЯ.fullmatch(в.attr)):
                поле = True
            if (isinstance(в, ast.Call) and isinstance(в.func, ast.Attribute) and в.func.attr in ("pop", "remove", "splice")) \
                    or isinstance(в, ast.Delete) \
                    or (isinstance(в, ast.Assign) and any(isinstance(ц, ast.Subscript) and isinstance(ц.slice, ast.Slice) for ц in в.targets)):
                скорочення = True
    return порівняння, поле, скорочення


def власне_правило_python(функції, ім, виклик):
    """Зв'язує змінені під умовою вікна дані з тілом саме цього HTTP-запиту через AST присвоєнь і параметрів."""
    def імена(вузол):
        """Ідентифікатори значення без слів із коментарів та рядків."""
        return {в.id for в in ast.walk(вузол) if isinstance(в, ast.Name)}

    def корінь(вузол):
        """Коренева змінна присвоєння чи мутації, зокрема `тіло['messages']`."""
        while isinstance(вузол, (ast.Attribute, ast.Subscript)):
            вузол = вузол.value
        return вузол.id if isinstance(вузол, ast.Name) else None

    граф, скорочені, черга, бачені, сталі = {}, set(), [ім], set(), []
    while черга:
        н = черга.pop()
        if н in бачені or н not in функції:
            continue
        бачені.add(н)
        функція = функції[н]
        for в in ast.walk(функція):
            if н == ім and getattr(в, 'lineno', 0) > виклик.lineno:
                continue
            if isinstance(в, (ast.Assign, ast.AnnAssign)) and в.value is not None:
                цілі = в.targets if isinstance(в, ast.Assign) else [в.target]
                for ціль in цілі:
                    for ц in ast.walk(ціль):
                        if isinstance(ц, ast.Name):
                            граф.setdefault(ц.id, set()).update(імена(в.value))
                if isinstance(в.value, ast.Constant) and isinstance(в.value.value, (int, float)):
                    for ціль in цілі:
                        for ц in імена(ціль):
                            if БЮДЖЕТ.search(ц) or ВІКНО.search(ц):
                                сталі.append('%s:%d=%s' % (ц, в.lineno, в.value.value))
            if isinstance(в, ast.Call) and isinstance(в.func, ast.Name) and в.func.id in функції:
                пом = функції[в.func.id]
                черга.append(пом.name)
                for п, а in zip(пом.args.args, в.args):
                    for зм in імена(а):
                        граф.setdefault(зм, set()).add(п.arg)
            if isinstance(в, (ast.If, ast.While)):
                умова = ast.unparse(в.test)
                if not (ТОКЕН.search(умова) and ВІКНО.search(умова)
                        and any(isinstance(к, ast.Compare) for к in ast.walk(в.test))):
                    continue
                for гілка in в.body:
                    for дія in ast.walk(гілка):
                        if (isinstance(дія, ast.Call) and isinstance(дія.func, ast.Attribute)
                                and дія.func.attr in ('pop', 'remove', 'splice')):
                            скорочені.add(корінь(дія.func.value))
    дані = залежності(граф, імена(виклик))
    return bool(дані & (скорочені - {None})), сталі


def місця_python(корінь, ф):
    """Місця Python: функція `джерела/*.py`, що шле запит серверові моделі — виклик `urlopen`/`requests.post` у функції, чиє
    тіло складає запит із ключем `messages`/`max_tokens` чи називає адресу `…/completions`. Проби (`проба*`), прилади, тести й гейти — вимір, не клас."""
    вих = []
    for ім_ф, шлях in файли_продукту(корінь, ".py"):
        with open(шлях, encoding="utf-8") as фх:
            текст = фх.read()
        if "urlopen" not in текст and "requests" not in текст:
            continue
        дерево = ast.parse(текст)
        функції = {в.name: в for в in ast.walk(дерево) if isinstance(в, (ast.FunctionDef, ast.AsyncFunctionDef))}
        for ім, функція in sorted(функції.items()):
            ключі = {к.value for д in ast.walk(функція) if isinstance(д, ast.Dict) for к in д.keys
                     if isinstance(к, ast.Constant) and isinstance(к.value, str)}
            ключі |= {к.arg for д in ast.walk(функція) if isinstance(д, ast.Call) for к in д.keywords if к.arg}
            адреса = any(isinstance(д, ast.Constant) and isinstance(д.value, str) and "completions" in д.value
                         for д in ast.walk(функція))
            if not (ключі & {"messages", "max_tokens"}) and not адреса:
                continue
            for в in ast.walk(функція):
                if isinstance(в, ast.Call) and isinstance(в.func, ast.Attribute) and в.func.attr in ("urlopen", "post"):
                    власне, сталі = власне_правило_python(функції, ім, в)
                    пункти, чому = порушення(True, "", ф, python_дії(функції, ім), власне, сталі)
                    вих.append(dict(файл=ім_ф, рядок=в.lineno, функція=ім, змінний=True,
                                    змінність="Python-клієнт моделі: промпт з даних", пункти=пункти, чому=чому,
                                    виклик_рядок="", виклик="python", шлях="python"))
    return вих


