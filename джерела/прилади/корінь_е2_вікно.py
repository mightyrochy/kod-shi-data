def вікна_серії(корінь, ім):
    шлях = os.path.join(корінь, "аудит", "проби", "б1", ім + ".md")
    if not os.path.exists(шлях):
        return {}
    with open(шлях, encoding="utf-8") as ф:
        текст = ф.read()
    return {м.group(1): int(м.group(2)) for м in re.finditer(r"`([^`]+)` \((?:ctx )?(\d{4,6})\)", текст)}


def записи_серії(корінь, ім, тека):
    """→ {вид: dict(вхід, стеля, модель, викликів, відмов)}; запити — теки з `знімки/модель_виклики.json`."""
    вікна = вікна_серії(корінь, ім)
    види, запитів, запитів_з_відмовою = {}, 0, set()
    for шлях in sorted(glob.glob(os.path.join(корінь, тека, "*", "знімки", "модель_виклики.json"))):
        запитів += 1
        with open(шлях, encoding="utf-8") as ф:
            дані = json.load(ф)
        for в in дані.get("виклики", []):
            вхід = в.get("вхід") or 0
            відмова = ВІДМОВА_ВІКНА.search(str(в.get("помилка") or ""))
            if відмова:
                вхід = max(вхід, int(відмова.group(1)))
                запитів_з_відмовою.add(шлях)
            з = види.setdefault(в["тип"], dict(вхід=0, стеля=0, модель=в.get("модель_сторінки"), викликів=0, відмов=0))
            з["викликів"] += 1
            з["відмов"] += 1 if відмова else 0
            з["вхід"] = max(з["вхід"], вхід)
            з["стеля"] = max(з["стеля"], в.get("стеля") or 0)
    for з in види.values():
        з["вікно"] = вікна.get(з["модель"])
    return види, запитів, len(запитів_з_відмовою)


def записи_місця(в, записи_всі):
    """Вид-и записів місця за ЗАПИСИ_МІСЦЬ (файл + якір у рядку виклику)."""
    for файл, якір, види in ЗАПИСИ_МІСЦЬ:
        if файл == в["файл"] and re.search(якір, в["виклик_рядок"]):
            return види
    return ()


def форма(з):
    if not з:
        return "—"
    разом = з["вхід"] + з["стеля"]
    вікно = з.get("вікно")
    return "%d т. + стеля %d = %d / %s%s" % (з["вхід"], з["стеля"], разом, вікно or "?",
                                           (" (%.0f %%)%s" % (100.0 * разом / вікно, " ВИЙШЛО" if разом > вікно else "")) if вікно else "")


