def очистити(текст):
    """→ (код, значення): обидва рівної довжини з `текст` (позиції й рядки збігаються). `код` — без коментарів і з
    порожнім вмістом рядків (`'…'`, `"…"`, `` `…` ``): слова в лапках чи коментарі дії не дають; `значення` — без
    коментарів, зі вмістом рядків (щоб побачити літерал і ключ `['n_ctx']`). Регулярні літерали не розбираються."""
    код, зн = [], []
    і, н, лапка = 0, len(текст), None
    while і < н:
        с = текст[і]
        if лапка:
            if с == "\\" and і + 1 < н:
                код.append("  "); зн.append(текст[і:і + 2]); і += 2
                continue
            if с == лапка:
                лапка = None
                код.append(с); зн.append(с)
            else:
                код.append("\n" if с == "\n" else " "); зн.append(с)
            і += 1
        elif текст.startswith("//", і) and текст[і - 1:і] != ":":
            к = текст.find("\n", і)
            к = н if к < 0 else к
            код.append(" " * (к - і)); зн.append(" " * (к - і)); і = к
        elif текст.startswith("/*", і):
            к = текст.find("*/", і + 2)
            к = н if к < 0 else к + 2
            п = "".join("\n" if ч == "\n" else " " for ч in текст[і:к])
            код.append(п); зн.append(п); і = к
        elif с in "'\"`":
            лапка = с
            код.append(с); зн.append(с); і += 1
        elif с == "/" and re.search(r"(?:[(,=:\[!&|?{};+*%<>~^-]|(?<![\w$])return|^)\s*$", текст[max(0, і - 12):і]):
            к, клас = і + 1, False          # регулярний літерал: ним лапки не відкриваються
            while к < н and текст[к] != "\n" and (клас or текст[к] != "/"):
                клас = (клас or текст[к] == "[") and текст[к] != "]"
                к += 2 if текст[к] == "\\" else 1
            к = min(н, к + 1)
            код.append("/" + " " * (к - і - 1)); зн.append(текст[і:к]); і = к
        else:
            код.append(с); зн.append(с); і += 1
    return "".join(код), "".join(зн)


def дужка(текст, відкрита):
    """Позиція парної закритої дужки для текст[відкрита] (у коді без рядків), чи len(текст)."""
    пара = {"(": ")", "[": "]", "{": "}"}[текст[відкрита]]
    глиб = 0
    for і in range(відкрита, len(текст)):
        if текст[і] in "([{":
            глиб += 1
        elif текст[і] in ")]}":
            глиб -= 1
            if not глиб:
                return і
    return len(текст)


def аргументи(код, значення, початок):
    """Аргументи виклику, дужка `(` якого стоїть у `код[початок]`: верхній рівень ділиться комами за кодом, текст — зі `значень`."""
    кінець = дужка(код, початок)
    вих, з, глиб = [], початок + 1, 0
    for і in range(початок + 1, кінець):
        if код[і] in "([{":
            глиб += 1
        elif код[і] in ")]}":
            глиб -= 1
        elif код[і] == "," and not глиб:
            вих.append(значення[з:і].strip()); з = і + 1
    вих.append(значення[з:кінець].strip())
    return [а for а in вих] if any(вих) else []


