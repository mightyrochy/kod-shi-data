    рядки.append("## Підсумки: п.1 — %d · п.2 — %d · п.3 — %d" % (пункти[1], пункти[2], пункти[3]))
    рядки.append("місць: %d" % len(порушують))
    if json_вихід:
        return json.dumps(dict(лійка=лійка, місця=місця_, місць=len(порушують)), ensure_ascii=False, indent=1, sort_keys=True)
    return "\n".join(рядки)


