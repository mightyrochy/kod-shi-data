def аргументи(текст, з_позиції):
    """Список верхнього рівня аргументів першого виклику `модельП(`/`модельП_блоки(` від позиції; дужки й лапки вкладені."""
    м = re.search(r"(?<![\w`])модельП(?:_блоки)?\(", текст[з_позиції:])
    if not м:
        return None, ""
    і = з_позиції + м.end()
    глиб, ціна, ящик, лапка = 1, [], [], None
    початок = і
    while і < len(текст) and глиб:
        с = текст[і]
        if лапка:
            if с == "\\":
                і += 1
            elif с == лапка:
                лапка = None
        elif с in "'\"`":
            лапка = с
        elif с in "([{":
            глиб += 1
        elif с in ")]}":
            глиб -= 1
            if not глиб:
                break
        elif с == "," and глиб == 1:
            ціна.append(текст[початок:і])
            початок = і + 1
        і += 1
    ціна.append(текст[початок:і])
    return м.group(0), [а.strip() for а in ціна]


def змінність(виклик, арг):
    """(змінний?, чому) — чи промпт місця складено з даних змінного обсягу."""
    а0 = арг[0] if арг else ""
    а1 = арг[1] if len(арг) > 1 else ""
    if виклик.startswith("модельП_блоки"):
        літерал = re.fullmatch(r"\[\s*\{\s*type\s*:\s*'text'\s*,\s*text\s*:\s*(?:'[^'$]*'|\"[^\"$]*\"|[А-ЯІЇЄҐA-Z0-9_]+)\s*\}\s*\]", а0)
        return (False, "літерал") if літерал else (True, "блоки з даних: " + а0[:40].replace("\n", " "))
    стала = re.fullmatch(r"[А-ЯІЇЄҐA-Z][А-ЯІЇЄҐA-Z0-9_]*|'[^'$]*'|\"[^\"$]*\"", а0)
    фото = а1 not in ("", "null", "undefined")
    if стала and not фото:
        return False, "стала без фото"
    return True, ("фото разом із промптом" if стала else "промпт з даних: " + а0[:40].replace("\n", " "))


def конус(корінь):
    """→ (імена функцій конуса лійки, текст коду конуса без коментарів, {ім: файл})."""
    тека = os.path.join(корінь, "джерела", "показ")
    функції, файли = {}, {}
    рядки_сталих = []
    for ім_ф in sorted(os.listdir(тека)):
        if not ім_ф.endswith(".js"):
            continue
        with open(os.path.join(тека, ім_ф), encoding="utf-8") as ф:
            текст = ф.read()
        чисте = М.без_коментарів_js(текст)
        for ім, _, тіло in М.функції_js(чисте):
            функції[ім] = тіло
            файли[ім] = ім_ф
        рядки_сталих += [(м.group(1), м.group(0)) for м in re.finditer(r"(?m)^(?:const|let|var)\s+(%s+)\s*=.*$" % БУКВА, чисте)]
    # лійка — самі ворота й те, що вони кличуть у два кроки (черга, планувальник, вміщення запиту, дзвінок); глибше
    # лежить увесь показ, і зайвий рядок про «токен» і «контекст» там не знає про вікно
    в_конусі, черга = set(), [(в, 0) for в in ВОРОТА if в in функції]
    while черга:
        ім, глиб = черга.pop(0)
        if ім in в_конусі:
            continue
        в_конусі.add(ім)
        if глиб < ГЛИБИНА_ЛІЙКИ:
            for інше in sorted(функції):
                if інше not in в_конусі and re.search(r"(?<!%s)%s(?!%s)" % (БУКВА, re.escape(інше), БУКВА), функції[ім]):
                    черга.append((інше, глиб + 1))
    текст_конуса = "\n".join(функції[і] for і in sorted(в_конусі))
    сталі = [р for ім, р in sorted(set(рядки_сталих)) if re.search(r"(?<!%s)%s(?!%s)" % (БУКВА, re.escape(ім), БУКВА), текст_конуса)]
    return sorted(в_конусі), текст_конуса + "\n" + "\n".join(сталі), функції, файли


def факти_лійки(корінь):
    """Що в КОДІ конуса лійки знає про вікно (п.1–3 однакові для всіх місць, бо лійка одна)."""
    імена, код, функції, _ = конус(корінь)
    рядки = код.split("\n")
    токени_з_вікном = [р.strip() for р in рядки if ТОКЕН.search(р) and ВІКНО.search(р) and not re.match(r"\s*(?:const|let|var)\s+МАКС_ТОКЕНІВ", р)]
    м = re.search(r"const\s+СТЕЛЯ_ЗАПИТУ_П\s*=\s*(\d+)", код)
    скорочення_у_функції = [ім for ім in імена
                            if any(ТОКЕН.search(р) and ВІКНО.search(р) for р in функції[ім].split("\n"))
                            and СКОРОЧЕННЯ.search(функції[ім])]
    літерали = []
    for шлях in sorted(glob.glob(os.path.join(корінь, "джерела", "показ", "*.js"))):
        with open(шлях, encoding="utf-8") as ф:
            чисте = М.без_коментарів_js(ф.read())
        for н, р in enumerate(чисте.split("\n"), 1):
            if ЛІТЕРАЛ_ВІКНА.search(р):
                літерали.append("%s:%d" % (os.path.relpath(шлях, корінь).replace(os.sep, "/"), н))
    return dict(функції_конуса=імена, токени_з_вікном=токени_з_вікном, поле_рушія=bool(ПОЛЯ_РУШІЯ.search(код)),
                стеля_символів=int(м.group(1)) if м else None, скорочує=скорочення_у_функції, літерали_вікна=літерали)


def місця(корінь):
    М.ПОКАЗ = os.path.join(корінь, "джерела", "показ")
    виклики, _ = М.виклики_js()
    ф = факти_лійки(корінь)
    вих = []
    for в in sorted(виклики, key=lambda x: (x["файл"], x["рядок"])):
        шлях = os.path.join(корінь, "джерела", в["файл"])
        with open(шлях, encoding="utf-8") as фх:
            текст = М.без_коментарів_js(фх.read())
        зсув = sum(len(р) + 1 for р in текст.split("\n")[:в["рядок"] - 1])
        виклик, арг = аргументи(текст, зсув)
        змін, чому_змін = змінність(виклик, арг)
        рядок_виклику = текст.split("\n")[в["рядок"] - 1]
        пункти, чому = [], []
        if змін:
            if not ф["токени_з_вікном"]:
                пункти.append(1)
                чому.append("у конусі лійки (%d функцій) токени не зіставлено з вікном: вхід міряє "
                            "`вмістити_запит_П` символами (стеля %s симв.)" % (len(ф["функції_конуса"]), ф["стеля_символів"]))
            if not ф["поле_рушія"] or ф["літерали_вікна"]:
                пункти.append(2)
                чому.append("вікна з налаштування рушія нема: поля %s у конусі не читаються%s"
                            % ("n_ctx/context_length", "; стала " + ", ".join(ф["літерали_вікна"]) if ф["літерали_вікна"] else ""))
            зріз = bool(арг and ЗРІЗ_СИМВОЛІВ.search(арг[0]))
            if not ф["токени_з_вікном"] or not ф["скорочує"] or зріз:
                пункти.append(3)
                чому.append("промпт, що не влазить, " + ("обрізається символами у виклику" if зріз else
                            "іде як є до відмови рушія (текст не скорочується, фото зменшуються лише за символами)"))
        вих.append(dict(файл=в["файл"], рядок=в["рядок"], функція=в["функція"], змінний=змін, змінність=чому_змін,
                        пункти=sorted(set(пункти)), чому=чому, виклик_рядок=рядок_виклику, виклик=виклик))
    return вих, ф


def клієнти_python(корінь):
    """Python-клієнти сервера моделі (інструменти каталогу): файл:рядок читання відповіді `choices`."""
    вих = []
    for шлях in sorted(glob.glob(os.path.join(корінь, "джерела", "*.py"))):
        ім = os.path.basename(шлях)
        if re.match(r"(?:тест|gate|audit|build_|стенд)", ім):
            continue
        with open(шлях, encoding="utf-8") as ф:
            for н, р in enumerate(ф, 1):
                if re.search(r"""(?:\[|get\()\s*["']choices["']""", р):
                    вих.append("джерела/%s:%d" % (ім, н))
    return вих


