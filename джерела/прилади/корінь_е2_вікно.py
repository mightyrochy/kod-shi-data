    рядки.append("- функції конуса: %s" % ", ".join(лійка["функції_конуса"]))
    рядки.append("- функцій у конусі: %d; умова `if/while` з порівнянням токенів і вікна: %s; читання поля вікна рушія: %s; "
                 "точка (усе разом із скороченням в одній функції): %s; літерали вікна в коді: %s"
                 % (len(лійка["функції_конуса"]), ", ".join(лійка["порівняння"]) or "нема",
                    ", ".join(лійка["поле_рушія"]) or "нема", ", ".join(лійка["точки"]) or "нема",
                    ", ".join(лійка["літерали_вікна"]) or "нема"))
