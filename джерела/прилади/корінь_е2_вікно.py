    рядки.append("")
    рядки.append("## Місця класу (виклик моделі зі змінним промптом): перелік `файл:рядок · функція · пункти · чому`")
    пункти = {1: 0, 2: 0, 3: 0}
    поза = []
    for в in місця_:
        мітка = "%s:%d · %s" % (в["файл"], в["рядок"], в["функція"])
        if not в["змінний"]:
            поза.append("%s (%s)" % (мітка, в["змінність"]))
            continue
        if в["пункти"]:
            порушують.append(в)
        for п in в["пункти"]:
            пункти[п] += 1
        види = записи_місця(в, None)
        рядки.append("%s · п.%s · %s · [%s]" % (мітка, ",".join(map(str, в["пункти"])) or "—", "; ".join(в["чому"]) or "порушень нема",
                                                  в["змінність"]))
        for ім, _ in СЕРІЇ:
            знайдені = [(вид, серії[ім][0].get(вид)) for вид in види if серії[ім][0].get(вид)]
            if знайдені:
                вид, з = max(знайдені, key=lambda x: x[1]["вхід"] + x[1]["стеля"])
                рядки.append("    %s: найбільший — %s (%s): %s" % (ім, вид, з["модель"], форма(з)))
            else:
                рядки.append("    %s: оцінка: запису нема (серія б1 не викликає це місце%s)" % (ім, "" if види else "; вид не прив'язано"))
    рядки.append("")
    if поза:
        рядки.append("## Виклики з літеральним промптом (поза класом): %d" % len(поза))
        рядки += ["- " + п for п in поза]
        рядки.append("")
    рядки.append("## Найбільший промпт за видом виклику (записи рушія)")
    прив = {вид for _, _, види in ЗАПИСИ_МІСЦЬ for вид in види}
    for ім, _ in СЕРІЇ:
        види, запитів, з_відмовою = серії[ім]
        рядки.append("### %s: запитів з записом %d, з відмовою рушія через вікно %d" % (ім, запитів, з_відмовою))
        for вид in sorted(види):
            з = види[вид]
            рядки.append("- %s (%s): %s · викликів %d · відмов вікна %d%s"
                         % (вид, з["модель"], форма(з), з["викликів"], з["відмов"], "" if вид in прив else " · вид без місця"))
    рядки.append("")
    рядки.append("## Підсумки: п.1 — %d · п.2 — %d · п.3 — %d" % (пункти[1], пункти[2], пункти[3]))
    рядки.append("місць: %d" % len(порушують))
    if json_вихід:
        return json.dumps(dict(лійка=лійка, місця=місця_, місць=len(порушують)), ensure_ascii=False, indent=1, sort_keys=True)
    return "\n".join(рядки)


