#!/usr/bin/env python3
"""Інвентар записів полів кореня Річ-кадр-варіант за класом 30.10.

Запуск з кореня: python джерела/прилади/корінь_річ_кадр_варіант.py
Опції: --інвентар (усі рішення), --json (машинний інвентар), --каталог.
Не виконує продукту, не робить мережевих запитів і не розпаковує каталог на диск.

Обхід знаходить записи, а не читання DOM чи кожний проміжний оператор.
Python: словники, dict/update, індексні й атрибутні присвоєння, setdefault,
XML, параметри трійками, текстова серіалізація та ключі записів. JS: лексичний
обхід властивостей об'єктів і присвоєнь, включно з обчислюваними ключами.
Імена полів не визначають клас: база містить семантичну роль, шлях у таблицю,
джерело й вибір у функції та три окремі рішення. База прив'язана до відбитка
запису й контексту функції; зсув рядків чи коментар не змінює рішення.
Відомі читачі й фікстури мають відбиток файла та пояснення виключення.
Новий запис, змінений контекст чи новий файл не успадковує виключення:
виводиться «нерозв'язано» та консервативно входить у число храповика.
Це статичний інвентар з переглянутою базою, не доказ виконання всіх гілок.
"""
import argparse
import ast
import collections
import gzip
import hashlib
import json
from pathlib import Path
import re
import sys
import warnings


ТУТ = Path(__file__).resolve()
БАЗА = ТУТ.with_suffix('.json')
СЛУЖБОВІ = {'node_modules', '__pycache__', '.git', '.venv', 'venv'}
РОЗШИРЕННЯ = {'.py', '.js', '.mjs', '.cjs'}
РОЛЬ = re.compile(r'фото|кадр|колір|кольор|свотч|наявн|доступн|'
                  r'^(?:images?|picture|colou?r|hex|lab|available|availability|'
                  r'in_stock|is_in_stock|stock_quantity|слово|є|url|адреса|файл)$', re.I)
ЛЕКСЕМА = re.compile(
    r'(?P<пропуск>\s+|//[^\n]*|/\*[\s\S]*?\*/)|'
    r'(?P<рядок>"(?:\\[\s\S]|[^"\\])*"|\'(?:\\[\s\S]|[^\'\\])*\'|'
    r'`(?:\\[\s\S]|[^`\\])*`)|(?P<імя>[^\W\d]\w*)|'
    r'(?P<оператор>===|!==|=>|==|!=|\?\?=|&&=|\|\|=|\+=|-=|\*\*|\?\.|.)', re.UNICODE)


def відбиток(значення):
    """Дає SHA256 канонічного JSON, незалежний від порядку словників і ОС."""
    return hashlib.sha256(json.dumps(значення, ensure_ascii=False, sort_keys=True,
                                    separators=(',', ':')).encode('utf-8')).hexdigest()


def структура(вузол):
    """Серіалізує AST без позицій і порожніх полів, доданих у нових Python."""
    if isinstance(вузол, ast.AST):
        return [type(вузол).__name__, [[к, структура(з)] for к, з in ast.iter_fields(вузол)
                if к not in {'type_params'}]]
    if isinstance(вузол, list):
        return [структура(ч) for ч in вузол]
    if isinstance(вузол, (str, int, float, bool)) or вузол is None:
        return вузол
    return repr(вузол)


def літерал(вузол):
    """Віддає буквальний ключ, а динамічний не домислює."""
    return str(вузол.value) if isinstance(вузол, ast.Constant) else '*'


def назва(вузол):
    """Віддає кінцеве ім'я виклику без виконання та імпорту модуля."""
    return getattr(вузол, 'attr', getattr(вузол, 'id', ''))


def записи_python(текст):
    """Відвідує кожен запис поля, зберігаючи його функцію й локальний контекст."""
    with warnings.catch_warnings():
        warnings.simplefilter('ignore', SyntaxWarning)
        дерево = ast.parse(текст)
    записи = []
    повтори = collections.Counter()
    контексти = {}

    def додати(вузол, поле, вид, область, контекст, вираз=None):
        """Вирізняє два однакові записи в одній функції без прив'язки до рядка."""
        ключ = відбиток([область, поле, вид, структура(вираз or вузол)])
        номер = повтори[ключ]
        повтори[ключ] += 1
        if id(контекст) not in контексти:
            контексти[id(контекст)] = відбиток(структура(контекст))
        записи.append({'ключ': ключ + ':' + str(номер), 'функція': область,
                       'поле': поле, 'вид': вид, 'рядок': вузол.lineno,
                       'контекст': контексти[id(контекст)]})

    def обійти(вузол, область='<модуль>', контекст=None):
        """Не змішує записи вкладених функцій із контекстом зовнішньої."""
        if isinstance(вузол, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            область += '.' + вузол.name
            контекст = вузол
        контекст = контекст or дерево
        if isinstance(вузол, ast.Dict):
            for ключ, значення in zip(вузол.keys, вузол.values):
                додати(ключ or значення, літерал(ключ), 'словник', область, контекст,
                       ast.Tuple(elts=[ключ or ast.Constant(value='**'), значення], ctx=ast.Load()))
        elif isinstance(вузол, ast.Assign):
            for ціль in вузол.targets:
                for ч in ast.walk(ціль):
                    if isinstance(ч, ast.Name) and re.search(r'ключ|дизайн|signature|fingerprint|^key$', ч.id, re.I):
                        додати(вузол, ч.id, 'ключ запису', область, контекст)
        elif isinstance(вузол, (ast.Subscript, ast.Attribute)) and isinstance(вузол.ctx, ast.Store):
            # XML .text належить уже знайденому SubElement, а не другому полю.
            if not (isinstance(вузол, ast.Attribute) and вузол.attr == 'text'
                    and isinstance(вузол.value, ast.Call) and назва(вузол.value.func) == 'SubElement'):
                поле = літерал(вузол.slice) if isinstance(вузол, ast.Subscript) else вузол.attr
                додати(вузол, поле, 'присвоєння', область, контекст)
        elif isinstance(вузол, ast.Call):
            ім = назва(вузол.func)
            if ім in {'dict', 'update', 'replace', 'setdefault', 'set', 'SubElement', 'Element'}:
                for ключ in вузол.keywords:
                    додати(ключ, ключ.arg or '*', 'іменований аргумент', область, контекст)
            if ім in {'setdefault', 'set', 'SubElement'} and вузол.args:
                номер = 1 if ім == 'SubElement' else 0
                if len(вузол.args) > номер:
                    додати(вузол, літерал(вузол.args[номер]), 'XML' if ім in {'set', 'SubElement'}
                           else 'setdefault', область, контекст)
            if ім in {'write', 'write_text', 'write_bytes'}:
                додати(вузол, '*текст', 'серіалізація', область, контекст)
        elif isinstance(вузол, (ast.List, ast.Tuple)) and isinstance(вузол.ctx, ast.Load):
            if (len(вузол.elts) in (2, 3) and isinstance(вузол.elts[0], ast.Constant)
                    and isinstance(вузол.elts[0].value, str) and РОЛЬ.search(вузол.elts[0].value)):
                додати(вузол, вузол.elts[0].value, 'параметр', область, контекст)
        elif isinstance(вузол, ast.Return) and вузол.value is not None:
            # Ключі двійників повертаються виразом, а не завжди полем dict.
            додати(вузол, '*повернення', 'повернення', область, контекст)
        for дитина in ast.iter_child_nodes(вузол):
            обійти(дитина, область, контекст)

    обійти(дерево)
    return записи


def записи_js(текст):
    """Інвентаризує властивості JS; літерали й коментарі не стають кодом."""
    токени = [(м.group(), м.start(), м.lastgroup) for м in ЛЕКСЕМА.finditer(текст)
              if м.lastgroup != 'пропуск']
    контекст = відбиток([т[0] for т in токени])
    записи, повтори = [], collections.Counter()
    for н, (токен, позиція, вид) in enumerate(токени):
        наступний = токени[н + 1][0] if н + 1 < len(токени) else ''
        попередній = токени[н - 1][0] if н else ''
        поле = None
        if наступний == ':' and вид in {'імя', 'рядок'}:
            поле = токен.strip('"\'')
        elif наступний in {'=', '+=', '-=', '??=', '||=', '&&='}:
            if попередній in {'.', '?.'}:
                поле = токен
            elif токен == ']':
                поле = токени[н - 1][0].strip('"\'') if токени[н - 1][2] == 'рядок' else '*'
        if поле is not None:
            ключ = відбиток([поле, [т[0] for т in токени[max(0, н - 4):н + 8]]])
            номер = повтори[ключ]
            повтори[ключ] += 1
            записи.append({'ключ': ключ + ':' + str(номер), 'функція': '<JS>',
                           'поле': поле, 'вид': 'JS', 'контекст': контекст,
                           'рядок': текст.count('\n', 0, позиція) + 1})
    return записи


def файли(корінь):
    """Дає весь Python/JS двох тек, включно з пробами й приладами-записувачами."""
    for ім in ('джерела', 'zhnyvarka'):
        for шлях in sorted((корінь / ім).rglob('*')):
            if шлях.suffix in РОЗШИРЕННЯ and not any(ч in СЛУЖБОВІ for ч in шлях.parts):
                yield шлях


def інвентар(корінь, база):
    """Звіряє живі координати записів з рішеннями, не друкує мертвих записів бази."""
    результат, перелік = [], []
    власна_тека = 'джерела/прилади/корінь_річ_кадр_варіант'
    for шлях in файли(корінь):
        файл = шлях.relative_to(корінь).as_posix()
        if файл.startswith(власна_тека):
            continue  # Прилад не пише таблиць продукту; не рахує сам себе.
        текст = шлях.read_text(encoding='utf-8-sig').replace('\r\n', '\n')
        опис = база.get('файли', {}).get(файл, {})
        хеш = відбиток(текст)
        перелік.append({'файл': файл, 'хеш': хеш})
        if опис.get('виключено') and опис.get('хеш') == хеш:
            continue
        try:
            записи = записи_python(текст) if шлях.suffix == '.py' else записи_js(текст)
        except (SyntaxError, ValueError) as помилка:
            записи = [{'ключ': '*розбір', 'рядок': getattr(помилка, 'lineno', 1),
                       'функція': '<модуль>', 'поле': '*розбір', 'контекст': хеш, 'вид': 'помилка'}]
        if not опис or опис.get('виключено'):
            записи = записи or [{'ключ': '*файл', 'рядок': 1, 'функція': '<модуль>',
                                 'поле': '*файл', 'контекст': хеш, 'вид': 'новий файл'}]
        for запис in записи:
            привязка = опис.get('записи', {}).get(запис['ключ'])
            оцінка = база['рішення'][привязка[1]] if привязка else {}
            if опис.get('контексти', {}).get(запис['функція']) != запис['контекст'] or not привязка:
                оцінка = {'роль': 'нерозв’язано', 'пункти': None,
                          'чому': 'новий запис або змінився контекст; потрібен перегляд джерела й вибору'}
            результат.append(dict(запис, файл=файл, **{к: оцінка[к] for к in ('роль', 'пункти', 'чому')}))
    return sorted(результат, key=lambda р: (р['файл'], р['рядок'], р['поле'], р['ключ'])), перелік


def каталог(корінь):
    """Звіряє компактні факти кадрів зі схемою читача та історичним числом 5664."""
    шлях = корінь / 'джерела/каталог_власник_кадру.json.gz'
    with gzip.open(шлях, 'rt', encoding='utf-8') as файл:
        дані = json.load(файл)
    записи = дані.get('записи', {})
    # У компактній схемі читати_факти немає поля варіанта: індекси 0..5 —
    # адреса, hash, членство в галереї, інші товари та два списки спільних файлів.
    відомих = sum(bool(з.get('варіант') and з['варіант'] != 'невідомо')
                  for з in записи.values() if isinstance(з, dict))
    кадрів = sum(bool(з[0]) if isinstance(з, list) else bool(з.get('кадр'))
                 for з in записи.values())
    return {'файл': шлях.relative_to(корінь).as_posix(), 'записів': len(записи),
            'кадрів_з_адресою': кадрів, 'без_адреси_кадру': len(записи) - кадрів,
            'відомих_варіантів': відомих, 'sha256_байтів': hashlib.sha256(шлях.read_bytes()).hexdigest(),
            'історична_звірка': '5664/5664 точок вжитку без варіанта (рядок 9686); це інша сукупність'}


def main():
    """Друкує рішення, підсумки та останній рядок контракту храповика."""
    if hasattr(sys.stdout, 'reconfigure'):
        sys.stdout.reconfigure(encoding='utf-8', newline='\n')
    ап = argparse.ArgumentParser(description=__doc__)
    ап.add_argument('дерево', nargs='?', type=Path, default=Path.cwd())
    ап.add_argument('--інвентар', action='store_true')
    ап.add_argument('--json', action='store_true')
    ап.add_argument('--каталог', action='store_true')
    арг = ап.parse_args()
    корінь = арг.дерево.resolve()
    if not (корінь / 'джерела').is_dir():
        ап.error('дерево має містити джерела/ та zhnyvarka/')
    база = json.loads(БАЗА.read_text(encoding='utf-8'))
    записи, перелік = інвентар(корінь, база)
    if арг.json:
        print(json.dumps({'записи': записи, 'файли': перелік}, ensure_ascii=False, sort_keys=True))
        return 0
    лічба = collections.Counter()
    нерозвязаних = місць = 0
    for з in записи:
        пункти = з['пункти']
        if пункти is None:
            нерозвязаних += 1
        if пункти or пункти is None:
            місць += 1
        if пункти or пункти is None or арг.інвентар:
            пункт = ','.join(map(str, пункти)) if пункти else 'нерозв’язано' if пункти is None else '0'
            print(f"{з['файл']}:{з['рядок']} · {пункт} · {з['функція']} / {з['поле']}: {з['чому']}")
        лічба.update(пункти or [])
    for пункт in (1, 2, 3):
        print(f'пункт {пункт}: {лічба[пункт]}')
    print(f'нерозв’язано: {нерозвязаних}')
    print(f'вирішено записів: {len(записи) - нерозвязаних}; файлів: {len(перелік)}')
    print('хеш рішень: ' + відбиток(записи))
    if арг.каталог:
        print('каталог: ' + json.dumps(каталог(корінь), ensure_ascii=False, sort_keys=True))
    print(f'місць: {місць}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
