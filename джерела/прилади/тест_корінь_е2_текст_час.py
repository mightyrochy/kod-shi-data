# -*- coding: utf-8 -*-
"""Перевіряє форми показу та обмежений обхід ромбів псевдонімів без продукту."""
import os
from pathlib import Path
import sys
import tempfile
import time
import unittest
from unittest.mock import patch

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import корінь_е2_текст_жінці as К


def вимір(код):
    """Лічить місця та відвідані стани на цілому малому дереві показу."""
    відвідано = []
    початковий = К.Походження._писачі_полів

    def стан(аналіз, ключ, поля, свій):
        """Рахує роботу графа, щоб тест не залежав від швидкості машини."""
        відвідано.append((ключ, поля, свій))
        return початковий(аналіз, ключ, поля, свій)

    with tempfile.TemporaryDirectory() as тека:
        корінь = Path(тека)
        (корінь / 'показ').mkdir()
        (корінь / 'показ.html').write_text('<input>', encoding='utf-8')
        (корінь / 'показ' / 'проба.js').write_text(код, encoding='utf-8')
        початок = time.perf_counter()
        with patch.object(К.Походження, '_писачі_полів', стан):
            _, стоки, *_ = К.обчислити(тека, ())
        секунди = time.perf_counter() - початок
        місця = sum(К.є_місцем(с) for с in стоки if not с.обгортка)
    return місця, len(відвідано), секунди


class ФормиПоказу(unittest.TestCase):
    """Тримає однакове мірило на замиканні, клоні параметра й ромбах."""

    def test_замикання_і_клон_параметра(с):
        """Динамічний текст лишається одним місцем у всіх чотирьох формах."""
        for замикання in (False, True):
            for клон in (False, True):
                запис = 'П = {текст: зовнішнє};'
                if замикання:
                    запис = 'function складатиП(){' + запис + '} складатиП();'
                код = 'let П = {}; function зібрати(){' + запис + '} зібрати();'
                код += 'function копія(запис){ return JSON.parse(JSON.stringify(запис)); }'
                код += 'document.body.textContent = ' + ('копія(П)' if клон else 'П') + '.текст;'
                with с.subTest(замикання=замикання, клон=клон):
                    місця, _, секунди = вимір(код)
                    print('замикання=%s, клон=%s: місць %d, %.4f с' % (замикання, клон, місця, секунди))
                    с.assertEqual(місця, 1)

    def test_ромби(с):
        """Кількість обходів залежить від станів, а не від числа шляхів до них."""
        for рівнів in (8, 20, 40):
            код = ['let П = {текст: зовнішнє}; let а0 = П; let б0 = П;']
            for і in range(1, рівнів):
                код.append(f'let а{і} = а{і-1}; а{і} = б{і-1}; let б{і} = а{і-1}; б{і} = б{і-1};')
            код.append(f'а{рівнів-1}.текст = зовнішнє;')
            код.append('document.body.textContent = П.текст;')
            with с.subTest(рівнів=рівнів):
                місця, стани, секунди = вимір('\n'.join(код))
                print('ромби: рівнів %d, місць %d, станів %d, %.4f с' % (рівнів, місця, стани, секунди))
                с.assertEqual(місця, 1)
                с.assertLessEqual(стани, 8 * рівнів + 16)

    def test_контексти_ключів_і_носіїв(с):
        """Кеш не змішує два виклики обгортки з різними ключами сховища."""
        код = '''
        function записати(ключ, текст){ localStorage.setItem(ключ, текст); }
        function читати(ключ){ return localStorage.getItem(ключ); }
        записати('її', document.querySelector('input').value);
        записати('код', зовнішнє);
        document.body.textContent = читати('її');
        document.body.title = читати('код');
        '''
        с.assertEqual(вимір(код)[0], 1)

    def test_ромби_зі_зворотним_присвоєнням(с):
        """Умовна пам'ять циклу прибирає повторний розбір його спільних гілок."""
        for рівнів in (8, 20, 40):
            код = ['let П = {текст: зовнішнє}; let а0 = П; let б0 = П;']
            for і in range(1, рівнів):
                код.append(f'let а{і} = а{і-1}; а{і} = б{і-1}; let б{і} = а{і-1}; б{і} = б{і-1};')
            код.append(f'а{рівнів-1}.текст = зовнішнє; П = а{рівнів-1}; document.body.textContent = П.текст;')
            with с.subTest(рівнів=рівнів):
                місця, стани, секунди = вимір('\n'.join(код))
                print('ромби з циклом: рівнів %d, місць %d, станів %d, %.4f с' % (рівнів, місця, стани, секунди))
                с.assertEqual(місця, 1)
                с.assertLessEqual(стани, 12 * (рівнів + 1) ** 2)


if __name__ == '__main__':
    unittest.main()
