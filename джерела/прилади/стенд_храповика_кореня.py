def прилад(умова="'МІСЦЕ' in р", файл='джерела/код.txt', кінець=''):
    """Текст приладу стенда: лічить рядки файлу за умовою й друкує «місць: N»."""
    return ('import sys\n'
            f"рядки = open({файл!r}, encoding='utf-8').read().splitlines()\n"
            f"print('місць:', sum(1 for р in рядки if {умова}))\n" + кінець)


def код(n, хвіст=''):
    """Текст «коду» з n місцями й чистим рядком."""
    return ''.join(f'рядок {і} МІСЦЕ\n' for і in range(n)) + 'чистий рядок\n' + хвіст


def паспорт(шлях='джерела/прилади/лічба.py', база=None):
    """Текст паспорта з рядком «прилад:» і, за потреби, «база:»."""
