def прилад(умова="'МІСЦЕ' in р", файл='джерела/код.txt', кінець=''):
    """Текст приладу стенда: лічить рядки файлу за умовою й друкує «місць: N»."""
    return ('import sys\n'
            f"рядки = open({файл!r}, encoding='utf-8').read().splitlines()\n"
            f"print('місць:', sum(1 for р in рядки if {умова}))\n" + кінець)


def прилад_з_помічником():
    """Прилад стенда, що бере мітку з помічника `спільне.py` своєї теки."""
