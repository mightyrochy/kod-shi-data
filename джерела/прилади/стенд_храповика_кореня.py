def записати(тека, файли):
    """Пише файли в дерево; вміст None — видаляє файл."""
    for шлях, вміст in файли.items():
        повний = os.path.join(тека, шлях)
        if вміст is None:
            os.remove(повний)
            continue
        os.makedirs(os.path.dirname(повний), exist_ok=True)
        with open(повний, 'w', encoding='utf-8') as ф:
            ф.write(вміст)


def git(тека, *аргументи):
    """Виконує git у тимчасовому репозиторії з підписом стенда; → stdout."""
    return subprocess.run(['git', '-C', тека, '-c', 'user.name=стенд', '-c', 'user.email=стенд@local',
                           '-c', 'commit.gpgsign=false', *аргументи],
                          capture_output=True, check=True, text=True).stdout.strip()


def прогнати(база, голова, храповик):
    """Будує репозиторій база → голова й запускає храповик як CI; → (код виходу, вивід + підсумок)."""
    with tempfile.TemporaryDirectory(prefix='стенд_храповика_') as тека:
        репо = os.path.join(тека, 'репо')
        os.makedirs(репо)
        git(репо, 'init', '-q', '-b', 'main')
        записати(репо, база)
        git(репо, 'add', '-A')
        git(репо, 'commit', '-q', '-m', 'база')
        sha_бази = git(репо, 'rev-parse', 'HEAD')
        записати(репо, голова)
        git(репо, 'add', '-A')
        git(репо, 'commit', '-q', '-m', 'голова')
        підсумок = os.path.join(тека, 'підсумок.md')
        середовище = dict(os.environ, GITHUB_STEP_SUMMARY=підсумок, GITHUB_ACTIONS='')
        вихід = subprocess.run([sys.executable, храповик, '--репо', репо, '--база', sha_бази],
                               capture_output=True, text=True, env=середовище)
        текст = вихід.stdout + вихід.stderr
        if os.path.exists(підсумок):
            with open(підсумок, encoding='utf-8') as ф:
                текст += '\n[підсумок]\n' + ф.read()
        return вихід.returncode, текст


def звірити(код_виходу, текст, червоний, є, нема):
    """Розбіжності виводу з очікуваним випадком; порожньо — як у таблиці наряду."""
    вади = []
    if код_виходу not in (0, 1):
        вади.append(f'код виходу {код_виходу}')
    elif (код_виходу == 1) != червоний:
        вади.append('червоний' if код_виходу == 1 else 'зелений')
    _, позначка, підсумок = текст.partition('\n[підсумок]\n')
    if not позначка:
        вади.append('підсумку роботи нема')
    вади += [f'у підсумку нема «{р}»' for р in є if р not in підсумок]
    вади += [f'зайве «{р}»' for р in нема if р in текст]
    return вади


def головний():
    """Проганяє всі випадки й друкує рядок мірила на кожен; код 1 — хоч один не той."""
    розбір = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    розбір.add_argument('--храповик', default=ХРАПОВИК, help='код роботи CI (ДО — шлях, якого нема)')
    храповик = розбір.parse_args().храповик
    збоїв = 0
    for номер, опис, червоний, варіанти in ВИПАДКИ:
        if not os.path.isfile(храповик):
            збоїв += 1
            print(f'мірило: випадок {номер} — нема перевірки ({храповик} нема)')
            continue
        вади, факти = [], []
        кольори, текст_вади = set(), ''
        for мітка, база, голова, є, нема, *свій in варіанти:
            черв = свій[0] if свій else червоний
            кольори.add('червоний' if черв else 'зелений')
            код_виходу, текст = прогнати(база, голова, храповик)
            свої_вади = звірити(код_виходу, текст, черв, є, нема)
            вади += [f'{мітка} {в}'.strip() for в in свої_вади]
            if свої_вади:
                текст_вади = текст
            ключ = є[0].lstrip('- ')
            факт = next((р.lstrip('- ') for р in текст.splitlines() if ключ in р), '—')
            факти.append(f'{мітка} {факт}'.strip())
        колір = ' і '.join(sorted(кольори, reverse=True))
        if вади:
            збоїв += 1
            print(f'мірило: випадок {номер} — НЕ ТАК ({опис}; чекали {колір}): {"; ".join(вади)}')
            print('  ' + текст_вади.replace('\n', '\n  '))
        else:
            print(f'мірило: випадок {номер} — {колір}, як очікувано ({опис}): {" | ".join(факти)}')
    print(f'стенд храповика: {len(ВИПАДКИ) - збоїв} з {len(ВИПАДКИ)} очікуваних')
    return 1 if збоїв else 0


if __name__ == '__main__':
    sys.exit(головний())
