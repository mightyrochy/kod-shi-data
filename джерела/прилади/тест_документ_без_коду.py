def тригери_pr():
    """Робочий процес → (є pull_request, є фільтр шляхів у pull_request)."""
    тек = os.path.join(КОРІНЬ, ".github", "workflows")
    підсумок = {}
    for ім_я in sorted(os.listdir(тек)):
        if not ім_я.endswith((".yml", ".yaml")):
            continue
        with open(os.path.join(тек, ім_я), encoding="utf-8") as ф:
            текст = ф.read()
        блок = re.search(r"^on:\n((?:[ \t].*\n|\n)*)", текст, re.M)
        pr = re.search(r"^  pull_request:\n((?:    .*\n)*)", блок.group(1), re.M) if блок else None
        підсумок[f".github/workflows/{ім_я}"] = (pr is not None,
                                                 bool(pr and re.search(r"^    paths(-ignore)?:", pr.group(1), re.M)))
    return підсумок


class Робочі(unittest.TestCase):
    def test_обов_язкові(self):
        т = тригери_pr()
        без_шляхів = tuple(sorted(к for к, (є, шляхи) in т.items() if є and not шляхи))
        self.assertEqual(без_шляхів, tuple(sorted(д.ОБОВЯЗКОВІ)))

    def test_шляхи_обгортки_ні(self):
        with open(os.path.join(КОРІНЬ, ".github/workflows/obhortka.yml"), encoding="utf-8") as ф:
            текст = ф.read()
        шляхи = re.findall(r"^      - '([^']+)'", текст, re.M)
        self.assertTrue(шляхи)
        for п in шляхи:
            зразок = п.replace("**", "x/y.md").replace("*", "x")
            self.assertFalse(д.шлях(зразок)[0], зразок)


