        self.assertIn("SHA: ${{ github.event.pull_request.head.sha }}", мітка)
        self.assertNotIn("checkout", мітка, "job фіксації мітки коду не бере")
        self.assertRegex(мітка, r"(?m)^      statuses: write$")
