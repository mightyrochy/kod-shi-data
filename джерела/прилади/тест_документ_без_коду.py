# ---------- черга concurrency (наряд CI-самозлиття-черга) ----------

ГРУПА_ДО = "самозлиття-документа"  # main 38fe7e9a: стала група для запуску від будь-якої події


def групи_з_yml(шлях=".github/workflows/samozlyttia.yml"):
    """Групи concurrency `samozlyttia.yml` → (група процесу | None, {job: (група, cancel-in-progress) | None},
    {job: умова `if`}). Група — стала назва: вираз `${{ … }}` у групі job — помилка тесту (модель треба розширити)."""
    with open(os.path.join(КОРІНЬ, шлях), encoding="utf-8") as ф:
        текст = ф.read()
    процесу = re.search(r"^concurrency:\n  group: (.+)\n", текст, re.MULTILINE)
    jobs, умови = {}, {}
    тіло = "\n".join(р for р in текст.split("\njobs:\n", 1)[1].splitlines() if not р.lstrip().startswith("#"))
    for блок in re.split(r"\n(?=  [A-Za-z_-]+:\n)", тіло):
        ім_я = re.match(r"\s*([A-Za-z_-]+):", блок).group(1)
        к = re.search(r"^    concurrency:\n      group: (.+)\n      cancel-in-progress: (\w+)\n", блок, re.MULTILINE)
        if к and "${{" in к.group(1):
            raise AssertionError(f"{ім_я}: група з виразом — модель її не обчислює: {к.group(1)}")
        jobs[ім_я] = (к.group(1).strip(), к.group(2) == "true") if к else None
        у = re.search(r"^    if: (.+)$", блок, re.MULTILINE)
        умови[ім_я] = у.group(1).strip() if у else ""
    return (процесу.group(1).strip() if процесу else None), jobs, умови


def черга(події, група, тривалість):
    """Модель черги concurrency GitHub (`cancel-in-progress: false`): у групі один запущений і один очікуваний,
    новіший очікуваний витісняє старший (скасовано).

    `події` — [(час, run_id, подія_тригера)] за часом; `група(подія, run_id)`; `тривалість(run_id)` — секунди.
    → {run_id: ("старт", час) | ("скасовано", час)}."""
    стан, підсумок = {}, {}  # група → [запущений (id, кінець) | None, очікуваний (id, подія) | None]

    def звільнити(до):
        while True:
            кінці = [(г[0][1], гр) for гр, г in стан.items() if г[0] and г[0][1] <= до]
            if not кінці:
                return
            кінець, гр = min(кінці)
            г = стан[гр]
            г[0] = None
            if г[1]:
                rid = г[1]
                г[1] = None
                підсумок[rid] = ("старт", кінець)
                г[0] = (rid, кінець + тривалість(rid))

    for час, rid, подія in події:
        звільнити(час)
        г = стан.setdefault(група(подія, rid), [None, None])
        if г[0] is None:
            підсумок[rid] = ("старт", час)
            г[0] = (rid, час + тривалість(rid))
        else:
            if г[1]:
                підсумок[г[1]] = ("скасовано", час)
            г[1] = rid
    звільнити(float("inf"))
    return підсумок


def інваріант(події, підсумок):
    """Завершення CI на PR, після якого жоден запуск від події PR не стартував (не обійшов PR) → [(час, run_id)]."""
    стартів_pr = [п[1] for rid, п in підсумок.items()
                  if п[0] == "старт" and {р: п_ for _, р, п_ in події}[rid] == "pull_request"]
    return [(час, rid) for час, rid, подія in події
            if подія == "pull_request" and not any(с >= час for с in стартів_pr)]


def _с(гг_хх_сс):
    г, х, с = map(int, гг_хх_сс.split(":"))
    return г * 3600 + х * 60 + с


def самозлиття(події, d_рішення, d_злиття):
    """Модель ПІСЛЯ (групи job): запуск від PR ставить `рішення` в чергу групи рішення; кінець рішення ставить
    `злиття` в чергу групи злиття; job після злиття груп самозлиття не тримають. Запуск від іншої події — без груп.
    `d_рішення(rid)`, `d_злиття(rid)` — секунди утримання групи (з чеканням раннера).
    → (рішення {rid: ("старт"|"скасовано", час)}, злиття {rid: …})."""
    pr = [(ч, rid, п) for ч, rid, п in події if п == "pull_request"]
    рішення = черга(pr, lambda п, rid: "рішення", d_рішення)
    готові = sorted((час + d_рішення(rid), rid, "pull_request") for rid, (що, час) in рішення.items() if що == "старт")
    return рішення, черга(готові, lambda п, rid: "злиття", d_злиття)


def затримка_злиття(події, рішення, злиття):
    """Для кожного завершення CI на PR (час t) — час, коли стартує злиття за рішенням, яке почалось не раніше t
    (воно обходить цей PR) → {rid: секунди | None — не обійдено}."""
    від_pr = {rid for _, rid, подія in події if подія == "pull_request"}  # запуск від push не обходить PR
    пари = sorted((рішення[rid][1], злиття[rid][1]) for rid, (що, _) in злиття.items()
                  if що == "старт" and rid in від_pr)
    вихід = {}
    for t, rid, подія in події:
        if подія != "pull_request":
            continue
        після = [з for р, з in пари if р >= t]
        вихід[rid] = (min(після) - t) if після else None
    return вихід


