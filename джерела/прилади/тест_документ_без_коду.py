def git(*а):
    return subprocess.run(["git", "-c", "core.quotepath=off", *а], cwd=КОРІНЬ, capture_output=True, text=True,
                          check=True).stdout


def коміти_історії():
    """Номер PR → squash-коміт на HEAD (історія з 10.11)."""
    вивід = git("log", "--since=2026-11-10T00:00Z", "--until=2026-11-12T23:59Z", "--author=mightyrochy",
                "--format=%H %s", "HEAD")
    знайдено = {}
    for р in вивід.splitlines():
        м = re.search(r"\(#(\d+)\)$", р)
        if м:
            знайдено.setdefault(int(м.group(1)), р.split(" ", 1)[0])
    return знайдено


def таблиця():
    рядки, розбіжностей = [], 0
    коміти = коміти_історії()
    for н in sorted(КЛАС, reverse=True):
        if н not in коміти:
            рядки.append(f"| #{н} | — | {КЛАС[н][0]} | коміту нема в історії | — |")
            continue
        так, перший, чому = д.вердикт(д.зміни_коміту(коміти[н], КОРІНЬ))
        прилад = "д" if так else "н"
        збіг = прилад == КЛАС[н][0]
        розбіжностей += not збіг
        рядки.append(f"| #{н} | `{коміти[н][:8]}` | {КЛАС[н][0]} ({КЛАС[н][1]}) | {прилад}"
                     f"{'' if так else f' — `{перший}`: {чому}'} | {'так' if збіг else 'НІ'} |")
    return рядки, розбіжностей, sum(1 for н in КЛАС if н in коміти)


КОМЕНТАР = ("#", "//", "/*", "* ", "<!--", "REM ", "::")


def посилання_коду():
    """Явні імена під дозволеними теками, які називає код (як у шапці приладу)."""
    файли = git("ls-files", "-z", "--", "джерела", ".github", ".claude", "zhnyvarka", "index.html", "аудит")
    код = []
    for ф in файли.split("\0"):
        ч = ф.split("/")
        if not ф or ф.endswith((".md", ".txt", ".png", ".jpg", ".webp", ".gz", ".jsonl", ".json", ".tsv", ".csv",
                                ".log", ".xml")):
            continue
        if ч[0] == "аудит" and not (ч[1] == "адаптери" or len(ч) == 2
                                     or (ч[1] == "проби" and len(ч) == 3)):
            continue  # скрипти в теках звітів — проби, не код CI
        код.append(ф)
    шаблон = re.compile(r"аудит/(проби|перевірка|перевірки|виміри|звіти|витрати|наряди|передачі)/"
                        r"([^/\"'` )\\,;:\n\]\[]+)")
    імена = {}
    for ф in код:
        try:
            with open(os.path.join(КОРІНЬ, ф), encoding="utf-8", errors="replace") as в:
                текст = в.read()
        except (IsADirectoryError, FileNotFoundError):
            continue
        for рядок in текст.splitlines():
            if рядок.lstrip().startswith(КОМЕНТАР):
                continue  # коментар цитує звіт як доказ, а не читає його
            for м in шаблон.finditer(рядок):
                імена.setdefault((м.group(1), м.group(2).rstrip(".…»")), ф)
    return імена


