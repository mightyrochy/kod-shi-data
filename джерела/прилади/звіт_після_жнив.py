# -*- coding: utf-8 -*-
"""Зберегти результати чинних проб каталогу після жнив, без гейта для жнив.

Свіжий XML підставляється в тимчасове дерево: проби зі сталими шляхами читають
його, а чистка не змінює вихід жнив. Збагачення/галереї лишаються знімками git.
"""
import argparse
import gzip
import hashlib
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

ЛІМІТ_СЕКУНД = 30
ПРЕФІКС = "каталог_проблеми_"


def відбиток(шлях):
    """Назвати джерело з хешем або чесно вказати його відсутність."""
    if not шлях.is_file():
        return f"`{шлях.name}` — немає"
    with шлях.open("rb") as вхід:
        хеш = hashlib.file_digest(вхід, "sha256").hexdigest()
    return f"`{шлях.name}` — sha256 `{хеш}`"


def дерево(корінь, тимчасове, каталог):
    """Підготувати легке дерево для чинних проб з ізольованим XML."""
    for шлях in корінь.iterdir():
        if шлях.name not in ("джерела", "каталог_повний.xml", "каталог_повний.xml.gz",
                              "каталог_записи_v1.jsonl.gz", "каталог_звіт_v1.json"):
            (тимчасове / шлях.name).symlink_to(шлях, target_is_directory=шлях.is_dir())
    джерела = тимчасове / "джерела"
    джерела.mkdir()
    for шлях in (корінь / "джерела").iterdir():
        if шлях.name not in ("проби", "__pycache__", "каталог_повний.xml", "каталог_повний.xml.gz"):
            (джерела / шлях.name).symlink_to(шлях, target_is_directory=шлях.is_dir())
    # Сама тека проб фізична: шлях «проби/../..» не має перейти в checkout.
    (джерела / "проби").mkdir()
    for шлях in (корінь / "джерела" / "проби").glob("*.py"):
        (джерела / "проби" / шлях.name).symlink_to(шлях)
    if каталог.is_file():
        архів = тимчасове / "каталог_повний.xml.gz"
        if каталог.suffix == ".gz":
            shutil.copyfile(каталог, архів)
        else:
            with каталог.open("rb") as вхід, gzip.open(архів, "wb") as вихід:
                shutil.copyfileobj(вхід, вихід)
    if каталог == корінь / "каталог_повний.xml.gz":
        for ім in ("каталог_записи_v1.jsonl.gz", "каталог_звіт_v1.json"):
            if (корінь / ім).is_file():
                (тимчасове / ім).symlink_to(корінь / ім)
    return джерела


def прогнати(проба, джерела, лог, секунд):
    """Запустити одну пробу; повернути rc та причину, не перериваючи решту."""
    # Ці проби потребують окремих входів, а не вигаданого виміру нових жнив.
    бракує = {
        "каталог_проблеми_в_перезбір.py": "потрібні HTML-знімки та url.json (три аргументи)",
        "каталог_проблеми_а_мережа.py": "мережевий вимір не виконується офлайн",
    }
    if проба.name in бракує:
        причина = бракує[проба.name]
        лог.write(причина + "\n")
        return "—", "немає входу: " + причина
    # Заборона мережі стосується й імпортів: цей звіт не запускає моделей/HTTP.
    запуск = ("import runpy,sys; "
              "sys.addaudithook(lambda подія,аргументи: "
              "(_ for _ in ()).throw(PermissionError('звіт: мережу вимкнено')) "
              "if подія in ('socket.connect','socket.getaddrinfo') else None); "
              "sys.argv=[sys.argv[1]]; runpy.run_path(sys.argv[0],run_name='__main__')")
    try:
        код = subprocess.run(
            [sys.executable, "-u", "-c", запуск, str(джерела / "проби" / проба.name)],
            cwd=джерела, stdout=лог, stderr=subprocess.STDOUT, timeout=секунд,
            env=dict(os.environ, PYTHONDONTWRITEBYTECODE="1", GIT_NO_LAZY_FETCH="1"),
            check=False).returncode
        return str(код), "виконано" if код == 0 else "помилка; див. лог (вхід/інструмент/проба)"
    except subprocess.TimeoutExpired:
        лог.write(f"\nчас вичерпано: {секунд} с\n")
        return "124", "час вичерпано; вимір неповний"
    except OSError as помилка:
        лог.write(f"\n{type(помилка).__name__}: {помилка}\n")
        return "—", "немає інструмента; див. лог"


def звіт(корінь, вихід, каталог, стан, секунд=ЛІМІТ_СЕКУНД):
    """Записати коротке зведення та всі stdout/stderr, навіть після збою проби."""
    вихід.mkdir(parents=True, exist_ok=True)
    проби = sorted((корінь / "джерела" / "проби").glob(ПРЕФІКС + "*.py"))
    рядки = ["\n## Діагностика каталогу після жнив\n",
             f"Стан кроку жнив/складання: `{стан}`. Діагностика не змінює його результат.\n",
             f"Каталог: `{каталог}`; {відбиток(каталог)}.\n",
             "XML — вхід цього звіту; збагачення, галереї, показ і архівні прогони — знімки checkout, не нові виміри жнив. "
             "Записи v1/звіт складальника від іншого каталогу не підставляються. Мережу вимкнено.\n"]
    for ім in ("каталог_збагачення.json.gz", "каталог_кадри.json.gz", "каталог_показ.json.gz"):
        рядки.append(відбиток(корінь / "джерела" / ім) + "\n")
    рядки.extend([f"\nПроб: {len(проби)}; межа однієї: {секунд} с. Повний stdout/stderr: `діагностика_каталогу.log`.\n",
                  "Новий клас проблем після розбору звіту — окремий фактичний рядок дошки; автоматичних правок дошки немає.\n",
                  "| Чинна проба / клас | rc | Результат |\n|---|---|---|\n"])
    збоїв = 0
    with tempfile.TemporaryDirectory(prefix="звіт-жнив-") as тека, (вихід / "діагностика_каталогу.log").open("w", encoding="utf-8") as лог:
        джерела = дерево(корінь, Path(тека), каталог)
        for проба in проби:
            лог.write(f"\n=== {проба.name} ===\n"); лог.flush()
            if каталог.is_file():
                код, причина = прогнати(проба, джерела, лог, секунд)
            else:
                код, причина = "—", "немає каталогу жнив; старий каталог не підставлено"
                лог.write(причина + "\n")
            збоїв += код != "0"
            рядки.append(f"| `{проба.stem.removeprefix(ПРЕФІКС)}` | {код} | {причина} |\n")
    рядки.append(f"\nВиконано з rc=0: {len(проби) - збоїв}; помилки/неповні виміри: {збоїв}. "
                  "rc=0 означає виконання проби, а не відсутність проблем каталогу.\n")
    if not проби:
        рядки.append("Проб не знайдено — діагностика відсутня.\n")
    текст = "\n".join(рядки)
    (вихід / "діагностика_каталогу.md").write_text(текст, encoding="utf-8")
    with (вихід / "звіт_жнив.md").open("a", encoding="utf-8") as файл:
        файл.write(текст)
    if os.environ.get("GITHUB_STEP_SUMMARY"):
        with open(os.environ["GITHUB_STEP_SUMMARY"], "a", encoding="utf-8") as файл:
            файл.write(текст)
    return int(bool(збоїв or not проби))


def головна():
    """Прочитати шляхи workflow і повернути стан діагностики окремо від жнив."""
    аргументи = argparse.ArgumentParser(description=__doc__)
    аргументи.add_argument("--вихід", type=Path, required=True)
    аргументи.add_argument("--каталог", type=Path, required=True)
    аргументи.add_argument("--стан", required=True)
    а = аргументи.parse_args()
    return звіт(Path(__file__).resolve().parents[2], а.вихід.resolve(), а.каталог.resolve(), а.стан)


if __name__ == "__main__":
    sys.exit(головна())
