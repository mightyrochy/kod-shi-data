# -*- coding: utf-8 -*-
"""Лічить функції інтерфейсу без повного шляху з розмови за паспортом Е2.

Обсяг — усі JS/HTML джерела/, крім лабораторії, тестів, проб і приладів.
Acorn розкриває області імен, передавання функцій і події; словник семантики
відрізняє дію продукту від вигляду й транспортного вводу. У словнику немає
числа чи списку порушень: наявність шляху, входу й виходу рахується з графа.
Нова дія не зникає через відсутність у словнику: саме замикання стає
окремим консервативним кандидатом, не зливаючись зі спільним помічником.

Шлях розмови не проходить крізь малювання/відкриття екранів: випадковий
виклик під час рендера не є інструментом моделі. Результат має дійти даними
до ЧАТ_П.push, включно з обгортками й поверненнями; стороння репліка не доказ.
Синтаксичний аналіз не доводить живої досяжності всіх умов і повноти полів.
Відомі межі й ручна вибірка — в Е2-усе-з-розмови-перелік.md.
"""
import argparse
from collections import deque
import hashlib
import json
from pathlib import Path
import subprocess
import sys

from е2_обробники import граф

ДАНІ = Path(__file__).with_name('е2_семантика.json')
РОЗМОВА = {'розмоваШаромП', 'розмоваЯкMainП'}
ЗУПИНКИ = {'режим', 'екран', 'відкритиПрофіль', 'відкритиАркуш', 'відкритиАркушПрофілю'}


def вигляд(ф):
    """Відділяє показ екрана від виклику дії моделлю."""
    return ф['назва'].startswith(('малювати', 'рендер')) or ф['назва'] in ЗУПИНКИ


def шлях(функції, початки, кінець, розмова=False):
    """Знаходить найкоротший ланцюжок викликів, не виконуючи реєстрацій UI."""
    черга = deque((і, [і]) for і in початки)
    бачені = set()
    while черга:
        і, слід = черга.popleft()
        if і in бачені:
            continue
        бачені.add(і)
        if і == кінець:
            return слід
        if розмова and вигляд(функції[і]):
            continue
        черга.extend((д, слід + [д]) for д in функції[і]['ребра'] if д not in бачені)
    return []


def досяжні(функції, початки):
    """Повертає виконувані з розмови вузли без переходів крізь екрани."""
    бачені, черга = set(), list(початки)
    while черга:
        і = черга.pop()
        if і in бачені:
            continue
        бачені.add(і)
        if not вигляд(функції[і]):
            черга.extend(функції[і]['ребра'])
    return бачені


def потік(функції, початки, дія, режим, потрібні=None, зерна=None, поля=None):
    """Простежує дані параметрів або результату через виклики, змінні й повернення."""
    обсяг = досяжні(функції, початки)
    if режим == 'вихід' and зерна is None and дія in обсяг and функції[дія]['приймачі']:
        return True
    мітки = {і: set() for і in обсяг}
    повернуто = set()
    if зерна is not None:
        for і, імена in зерна.items():
            if і in мітки:
                мітки[і].update(імена)
    elif режим == 'вхід':
        for і in початки:
            мітки[і].update(функції[і]['параметри'])
            мітки[і].update(('ЧАТ_П', 'ПАСПОРТ_П', 'ФОТО_ВКЛАДЕНІ_П'))
    зміна = True
    while зміна:
        зміна = False
        for і in sorted(обсяг):
            ф, лок = функції[і], мітки[і]
            було = len(лок)
            for запис in ф['потоки']:
                if лок.intersection(запис['з']):
                    лок.add(запис['ціль'])
            for к in ф['виклики']:
                цілі = set(к['цілі']) & обсяг
                if цілі.intersection(повернуто) or (режим == 'вихід' and зерна is None and дія in цілі):
                    лок.add('@' + str(к['ід']))
                for ціль in цілі:
                    for н, залежності in enumerate(к['вхід']):
                        параметри = функції[ціль]['параметри']
                        if н < len(параметри) and лок.intersection(залежності):
                            до = len(мітки[ціль])
                            мітки[ціль].add(параметри[н])
                            зміна |= len(мітки[ціль]) != до
            if лок.intersection(ф['повернення']) and і not in повернуто:
                повернуто.add(і)
                зміна = True
            зміна |= len(лок) != було
    if режим == 'вхід':
        параметри = функції[дія]['параметри']
        потрібні = list(range(len(параметри))) if потрібні is None else потрібні
        передані = {з['елемент'] for і in обсяг for з in функції[і]['дом_записи']
            if мітки[і].intersection(з['з'])}
        return set(поля or []) <= передані and all(
            н < len(параметри) and параметри[н] in мітки.get(дія, set()) for н in потрібні)
    return any(мітки[і].intersection(функції[і]['приймачі']) for і in обсяг)


def підтвердження_стану(функції, початки, дія, договір):
    """Доводить спільний об'єкт застосованого стану й тексту підтвердження.

    Дії з побічним записом можуть не повертати результат. Для такого договору
    недостатньо будь-якої репліки: ті самі дані мусять дійти до адаптера, що
    викликає дію, і до тексту чату. Джерело даних задає семантичний словник.
    """
    for і in початки:
        ф = функції[і]
        if ф['назва'] != договір['розмова']:
            continue
        джерела = {к['ід'] for к in ф['виклики'] if к['назва'] == договір['джерело']
            and any(договір['поле'] in а for а in к['поля'])}
        змінні = {п['ціль'] for п in ф['потоки'] if any('@' + str(к) in п['з'] for к in джерела)}
        for адаптер in функції:
            ціль = адаптер['ід']
            if адаптер['назва'] != договір['адаптер'] or not шлях(функції, [ціль], дія):
                continue
            зерна = {і: змінні}
            if потік(функції, [і], ціль, 'вхід', [0], зерна) and потік(функції, [і], дія, 'вихід', зерна=зерна):
                return True
    return False


def відбиток_контексту(функції, і):
    """Прив'язує виключення до тіла обробника й цілей досяжних записувачів.

    Тіла помічників не входять у контекст: незмінна дія переживає їхню
    внутрішню правку. Новий записувач або нова ціль навіть глибокого запису
    змінює контекст. Обчислений ключ теж запис, із нерозв'язаним виразом.
    """
    записи = []
    for н in досяжні(функції, [і]):
        ф = функції[н]
        if вигляд(ф):
            continue
        цілі = dict(записи=sorted({з['ціль'] for з in ф['записи']}),
            приймачі=sorted({к['назва'].removeprefix('window.') for к in ф['виклики']
                if к['назва'] in ('ЧАТ_П.push', 'window.ЧАТ_П.push')}),
            дом=sorted({з['елемент'] for з in ф['дом_записи']}),
            сховище=sorted({json.dumps(з, ensure_ascii=False, sort_keys=True)
                for з in ф['сховище_записи']}))
        if any(цілі.values()):
            записи.append(json.dumps(dict(функція=ф['файл'] + ':' + ф['назва'], **цілі),
                ensure_ascii=False, sort_keys=True))
    контекст = [функції[і]['відбиток'], sorted(записи)]
    return hashlib.sha256(json.dumps(контекст, ensure_ascii=False).encode()).hexdigest()


def назва_вузла(ф):
    """Формує адресу функції, включно з анонімним обробником."""
    return f"{ф['файл']}:{ф['рядок']} {ф['назва'] or 'обробник@' + str(ф['стовпець'])}"


def вимір(дані, семантика=None):
    """Класифікує всі обробники й лічить унікальні функції з розривом шляху."""
    семантика = семантика or {'обробники': {}, 'дії': {}}
    функції, обробники = дані['функції'], дані['обробники']
    початки = [ф['ід'] for ф in функції if ф['назва'] in РОЗМОВА]
    результат, групи, контексти = [], {}, {}
    невідомих = 0
    for о in обробники:
        і = о['ціль']
        if і is None:
            raise ValueError(f"{о['файл']}:{о['рядок']}: не розкрито обробник {о['код']}")
        ф = функції[і]
        ключ = ф['файл'] + ':' + ф['відбиток']
        опис = семантика['обробники'].get(ключ, {})
        рядок = dict(обробник=f"{о['файл']}:{о['рядок']}", подія=о['подія'],
            замикання=назва_вузла(ф), ключ=ключ)
        if 'не_місце' in опис:
            if і not in контексти:
                контексти[і] = відбиток_контексту(функції, і)
            if контексти[і] in [опис['контекст'], *опис.get('інші_контексти', [])]:
                рядок.update(стан='не місце', причина=опис['не_місце'])
                результат.append(рядок)
                continue
            опис = {}
        дії = опис.get('дії', [])
        if not дії:
            невідомих += 1
            дії = [dict(вузол=і, назва=ф['назва'] or 'нова дія інтерфейсу')]
            рядок['потребує_звірки'] = True
        сліди = []
        for запис in дії:
            дія = семантика['дії'][запис] if isinstance(запис, str) else запис
            if 'вузол' in дія:
                ціль = дія['вузол']
            elif дія.get('функція') == '<обробник>':
                ціль = і
            else:
                кандидати = [в['ід'] for в in функції if в['назва'] == дія['функція']
                    and в['файл'] == дія['файл'] and шлях(функції, [і], в['ід'])]
                if len(кандидати) != 1:
                    raise ValueError(f"{назва_вузла(ф)}: дія {дія['назва']} має {len(кандидати)} цілей")
                ціль = кандидати[0]
            ланцюжок = шлях(функції, [і], ціль)
            if not ланцюжок:
                raise ValueError(f"{назва_вузла(ф)}: немає виклику дії {дія['назва']}")
            if ціль not in групи:
                з_розмови = шлях(функції, початки, ціль, розмова=True)
                бракує = []
                if not з_розмови:
                    бракує.append('інструмента')
                else:
                    if not потік(функції, початки, ціль, 'вхід', дія.get('вхід'), поля=дія.get('вхід_поля')):
                        бракує.append('передавання з розмови')
                    if not потік(функції, початки, ціль, 'вихід') and not (
                        дія.get('підтвердження_стану') and підтвердження_стану(
                            функції, початки, ціль, дія['підтвердження_стану'])):
                        бракує.append('показу результату')
                групи[ціль] = dict(функція=назва_вузла(функції[ціль]), назва=дія['назва'],
                    бракує=бракує, інтерфейс=[], шлях_розмови=[назва_вузла(функції[н]) for н in з_розмови])
            слід = dict(дія=групи[ціль]['функція'], шлях=[назва_вузла(функції[н]) for н in ланцюжок])
            групи[ціль]['інтерфейс'].append(dict(адреса=рядок['обробник'], подія=о['подія'], шлях=слід['шлях']))
            сліди.append(слід)
        рядок.update(стан='місце' if any(г['бракує'] for г in групи.values()
            if any(с['дія'] == г['функція'] for с in сліди)) else 'не місце', дії=сліди)
        результат.append(рядок)
    return dict(місця=[г for г in групи.values() if г['бракує']], функції=list(групи.values()),
        обробники=результат, невідомих=невідомих, файли=дані['файли'])


def main():
    """Друкує відтворюваний перелік або JSON; останній рядок лічби — місць: N."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('--корінь', default='.')
    парсер.add_argument('--json', action='store_true')
    арг = парсер.parse_args()
    try:
        дані = вимір(граф(арг.корінь), json.loads(ДАНІ.read_text(encoding='utf-8-sig')))
        if арг.json:
            print(json.dumps(дані, ensure_ascii=False, indent=2))
        else:
            for м in дані['місця']:
                print(f"{м['функція']} — {м['назва']}; бракує: {', '.join(м['бракує'])}")
            print(f"файлів: {len(дані['файли'])}; обробників: {len(дані['обробники'])}; "
                  f"функцій продукту: {len(дані['функції'])}; нових/змінених до звірки: {дані['невідомих']}")
            print(f"місць: {len(дані['місця'])}")
    except (OSError, ValueError, subprocess.CalledProcessError) as помилка:
        print(f'помилка приладу Е2: {помилка}\n{getattr(помилка, "stderr", "")}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    sys.stderr.reconfigure(encoding='utf-8')
    sys.exit(main())
