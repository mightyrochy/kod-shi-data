# -*- coding: utf-8 -*-
"""ЗГОРТАННЯ ПАСПОРТІВ: файли `аудит/корені/<корінь>.d/**/*.md` → текст `аудит/корені/<корінь>.md`, файли видаляє.

ДЕ ЩО ЛЕЖИТЬ (наряд «Паспорт-шапка-й-історія», диспетчер 20.11). Паспорт `аудит/корені/<корінь>.md` — ШАПКА (проблема,
клас, інваріант, напрямок, мірило, чинні рішення, «що лишилось»); датовані кроки й дослідження —
у файлі історії `аудит/корені/історія/<корінь>.md` (поділ — `поділити_паспорти.py`; теку історії читачі паспортів не
бачать будовою, див. його шапку). Тому: запис файла гілки («додати») доточується в кінець ІСТОРІЇ, а блок
`<<<< замінити … ==== на … >>>>` застосовується до ШАПКИ — через нього крок оновлює «Що лишилось», число приладу чи
відмітку стану, і шапка не росте щоденником. Старий текст заміни, якого в шапці нема (він у історії чи його нема
взагалі), — помилка з назвою файла. Нема файла історії — перший запис створює його з преамбулою.

ЩО ЦЕ ЛАГОДИТЬ (менеджер 15.11, доручення «Паспорт-файл-гілки»). Кожен крок кореня дописував зроблене в паспорт, і над
вирішеною правкою, коли частини йдуть паралельно, кожне злиття однієї частини робило конфліктним паспорт у всіх інших
відкритих гілок кореня: 15.11 сім частин Е3-сила-правила (#3923, #3902, #3922, #3917, #3911, #3910, #3912) зливались
по одній на годину — злити `main` у гілку, CI ~40 хв, злиття, і знову конфлікт у решти. Дошка цієї вади не має
(`згорнути_дошку.py`); паспорт тепер — так само: крок пише свій запис окремим файлом гілки (гілка `claude/x` →
`аудит/корені/<корінь>.d/claude/x.md`), а після злиття в `main` CI згортає файл у паспорт тим самим кроком, що дошку
(`zbirka.yml`, job publish, з тим самим захистом від гонки пушів у `main`), і видаляє його.

ФОРМАТ ФАЙЛА ГІЛКИ (кінець — `.md`; будь-що інше в `.d/` — помилка з назвою файла):
  <!-- … -->                         однорядковий коментар — пропускається (шапка: що за крок і з якої гілки)
  будь-який інший текст               запис: дописується в кінець ІСТОРІЇ кореня як є (звичайно розділ «## …» чи «### …»),
                                      порожній рядок між записами; хто пише «Що лишилось» — дописує новий розділ
  <<<< замінити                       зміна наявного тексту ШАПКИ паспорта (число приладу, «Що лишилось», відмітка стану):
  <точний старий текст>               він мусить стояти в шапці РІВНО один раз (кілька рядків можна),
  ==== на                            інакше — помилка (нема — «вже було», якщо там уже стоїть новий текст)
  <новий текст>
  >>>>
Елементи файла застосовуються в порядку файла, файли — у порядку злиття: за першим комітом, що додав файл, у
`git log --first-parent` `main`; файл, якого історія не знає (неглибокий клон), — після відомих, за назвою.

ЩО НЕ МОВЧИТЬ. Файл без паспорта (нема `<корінь>.md` чи його перший рядок не «# Корінь …»), не `.md`, порожній, із
незакритим блоком заміни, зі старим текстом, якого в паспорті нема чи який стоїть там кілька разів, — «ПОМИЛКА
<файл>: …», код виходу 1; такий файл не згортається й не видаляється ні частково, ні цілком (решта згортається).
У PR (`--лише-перевірити`) це червоний CI голови з назвою файла.
ПОВТОР. Файл після згортання видалено, тож повторний запуск нічого не міняє; запис, що вже стоїть у паспорті цілими
рядками (PR устиг вписати й туди), — не помилка: пропущено, у звіті «вже було».

ЗАПУСК (з кореня репозиторію):
    python3 джерела/прилади/згорнути_паспорти.py                    # згорнути й видалити файли
    python3 джерела/прилади/згорнути_паспорти.py --лише-перевірити  # нічого не писати (перевірка PR)
"""
import os
import re
import subprocess
import sys

# Каталог скрипта відсутній у sys.path під `python -I` у CI й стенді.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from поділити_паспорти import преамбула_історії, шлях_історії

КОРІНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ТЕКА = os.path.join(КОРІНЬ, 'аудит', 'корені')
КОМЕНТАР = re.compile(r'^<!--.*-->\s*$')
ВІДКРИТТЯ, СЕРЕДИНА, КІНЕЦЬ = '<<<< замінити', '==== на', '>>>>'


def теки_записів():
    """Теки `<корінь>.d` у `аудит/корені` → відносні шляхи всіх файлів усередині (не лише `.md`)."""
    if not os.path.isdir(ТЕКА):
        return []
    файли = []
    for назва in sorted(os.listdir(ТЕКА)):
        тека = os.path.join(ТЕКА, назва)
        if назва.endswith('.d') and os.path.isdir(тека):
            for кат, _, імена in os.walk(тека):
                файли += [os.path.relpath(os.path.join(кат, і), КОРІНЬ) for і in імена]
    return sorted(файли)


def корінь_файла(відносний):
    """`аудит/корені/<корінь>.d/…` → `<корінь>`."""
    return відносний.split(os.sep)[2][:-2]


def паспорт_існує(корінь):
    шлях = os.path.join(ТЕКА, корінь + '.md')
    if not os.path.isfile(шлях):
        return False
    with open(шлях, encoding='utf-8') as ф:
        return ф.readline().startswith('# Корінь ')


def порядок_злиття(файли):
    """Файли → у порядку першого коміту, що додав їх у `--first-parent` історії; невідомі — наприкінці за назвою."""
    індекс = {}
    try:
        вивід = subprocess.run(
            ['git', '-c', 'core.quotepath=off', 'log', '--first-parent', '-m', '--reverse', '--diff-filter=A',
             '--name-only', '--format=@%H', '--', 'аудит/корені'],
            cwd=КОРІНЬ, capture_output=True, text=True, encoding='utf-8', check=True).stdout
        n = 0
        for р in вивід.splitlines():
            if р.startswith('@'):
                n += 1
            elif р and р not in індекс:
                індекс[р] = n
    except (OSError, subprocess.CalledProcessError):
        pass
    return sorted(файли, key=lambda ф: (ф.replace(os.sep, '/') not in індекс,
                                      індекс.get(ф.replace(os.sep, '/'), 0), ф))


def прочитати(відносний):
    """Читає елементи з номерами рядків доданого чи нового тексту та помилки."""
    елементи, помилки = [], []
    if not відносний.endswith('.md'):
        return [], ['у `.d/` лише `.md` — файл не буде згорнуто']
    with open(os.path.join(КОРІНЬ, відносний), encoding='utf-8') as ф:
        рядки = [р.rstrip('\r') for р in ф.read().split('\n')]
    буфер, i = [], 0

    def скинути():
        while буфер and not буфер[0][1]:
            буфер.pop(0)
        while буфер and not буфер[-1][1]:
            буфер.pop()
        текст = '\n'.join(р for _, р in буфер)
        if текст.strip():
            елементи.append(('додати', текст, [н for н, _ in буфер]))
        буфер.clear()

    while i < len(рядки):
        р = рядки[i]
        if р.strip() == ВІДКРИТТЯ:
            скинути()
            старе, нове, де, початок_нового = [], [], 'старе', 0
            п = i + 1
            while п < len(рядки) and рядки[п].strip() != КІНЕЦЬ:
                if рядки[п].strip() == СЕРЕДИНА and де == 'старе':
                    де = 'нове'
                    початок_нового = п + 2
                else:
                    (старе if де == 'старе' else нове).append(рядки[п])
                п += 1
            if п >= len(рядки) or де == 'старе':
                помилки.append(f'рядок {i + 1}: блок «{ВІДКРИТТЯ}» без «{СЕРЕДИНА}» чи без «{КІНЕЦЬ}»')
                break
            старий_текст, новий_текст = '\n'.join(старе), '\n'.join(нове)
            с, н = старий_текст.strip('\n'), новий_текст.strip('\n')
            if not с.strip():
                помилки.append(f'рядок {i + 1}: старий текст заміни порожній')
            else:
                пропуск = len(новий_текст) - len(новий_текст.lstrip('\n'))
                номери = list(range(початок_нового + пропуск, початок_нового + пропуск + len(н.split('\n'))))
                if not н:
                    номери = [i + 2 + len(старий_текст) - len(старий_текст.lstrip('\n'))]
                елементи.append(('замінити', с, н, номери))
            i = п + 1
            continue
        if not КОМЕНТАР.match(р):
            буфер.append((i + 1, р))
        i += 1
    скинути()
    if not елементи and not помилки:
        помилки.append('порожній файл: ні запису, ні заміни')
    return елементи, помилки


def містить_рядками(текст, шматок):
    return ('\n' + шматок + '\n') in ('\n' + текст + '\n')


def застосувати(шапка, історія, елементи):
    """→ (шапка, історія, дописано, замін, вже було, помилки); помилка — тексти не міняються ніким із елементів файла.

    Запис («додати») доточується в кінець ІСТОРІЇ кореня; заміна — у тексті ШАПКИ (паспорта): там «Що лишилось», число
    приладу, відмітки стану. «Вже було» — запис чи новий текст стоїть уже де-небудь у шапці або історії.
    """
    дописано = замін = було = 0
    помилки = []
    початкова_шапка, початкова_історія = шапка, історія
    походження = [None] * len(шапка)
    for е in елементи:
        новий_текст, номери = е[-2:]
        джерела = [н for н, р in zip(номери, новий_текст.splitlines(keepends=True)) for _ in р]
        if е[0] == 'додати':
            if містить_рядками(історія, е[1]) or містить_рядками(шапка, е[1]):
                було += 1
            else:
                історія = історія.rstrip('\n') + '\n\n' + е[1] + '\n'
                дописано += 1
        else:
            _, старе, нове, _ = е
            n = шапка.count(старе)
            if n == 1:
                початок = шапка.index(старе)
                походження[початок:початок + len(старе)] = джерела
                if not нове and походження:
                    походження[min(початок, len(походження) - 1)] = номери[0]
                шапка = шапка.replace(старе, нове, 1)
                замін += 1
            elif n == 0 and нове and (нове in шапка or нове in історія):
                було += 1
            elif n == 0:
                помилки.append(f'старого тексту заміни нема в шапці паспорта (заміна — лише в шапці; історія лише '
                               f'дописується): «{старе.split(chr(10))[0][:70]}»')
            else:
                помилки.append(f'старий текст заміни стоїть у шапці паспорта {n} разів, потрібен рівно один: '
                               f'«{старе.split(chr(10))[0][:70]}»')
    if помилки:
        return початкова_шапка, початкова_історія, дописано, замін, було, помилки
    return шапка, історія, дописано, замін, було, помилки


def прочитати_історію(корінь):
    """Текст історії кореня; нема файла — преамбула нової історії (файл створить перший запис)."""
    шлях = шлях_історії(корінь)
    if os.path.isfile(шлях):
        with open(шлях, encoding='utf-8') as ф:
            return ф.read()
    return '\n'.join(преамбула_історії(корінь)) + '\n'


def записати_файл(шлях, текст):
    os.makedirs(os.path.dirname(шлях), exist_ok=True)
    тимчасовий = шлях + '.tmp'
    with open(тимчасовий, 'w', encoding='utf-8') as ф:
        ф.write(текст)
    os.replace(тимчасовий, шлях)


def згорнути(лише_перевірити=False):
    файли, помилки = теки_записів(), []
    тексти, історії, справні = {}, {}, []
    дописано = замін = було = 0
    for відносний in порядок_злиття(файли):
        корінь = корінь_файла(відносний)
        елементи, пом = прочитати(відносний)
        if not паспорт_існує(корінь):
            пом.append(f'корінь «{корінь}»: нема паспорта `аудит/корені/{корінь}.md` із першим рядком «# Корінь …»')
        if not пом:
            if корінь not in тексти:
                with open(os.path.join(ТЕКА, корінь + '.md'), encoding='utf-8') as ф:
                    тексти[корінь] = ф.read()
                історії[корінь] = прочитати_історію(корінь)
            шапка, історія, д, з, б, пом = застосувати(тексти[корінь], історії[корінь], елементи)
            if not пом:
                тексти[корінь], історії[корінь] = шапка, історія
                дописано, замін, було = дописано + д, замін + з, було + б
                справні.append(відносний)
        назва = відносний.replace(os.sep, '/')
        помилки += [f'{назва}: {п}' for п in пом]
    звіт = (f'файлів {len(файли)}, згорнуто {len(справні)}; дописано в історію {дописано}, замін у шапці {замін}, '
            f'вже було {було}; помилок {len(помилки)}')
    if not лише_перевірити and справні:
        for корінь, текст in тексти.items():
            записати_файл(os.path.join(ТЕКА, корінь + '.md'), текст)
            if історії[корінь] != прочитати_історію(корінь):  # нову історію без записів не створюємо
                записати_файл(шлях_історії(корінь), історії[корінь])
        for відносний in справні:
            os.remove(os.path.join(КОРІНЬ, відносний))
        for назва in sorted(os.listdir(ТЕКА)):
            тека = os.path.join(ТЕКА, назва)
            if назва.endswith('.d') and os.path.isdir(тека):
                for кат, _, _ in sorted(os.walk(тека), reverse=True):
                    if not os.listdir(кат):
                        os.rmdir(кат)
    return звіт, помилки


if __name__ == '__main__':
    звіт, помилки = згорнути('--лише-перевірити' in sys.argv)
    print(звіт)
    for п in помилки:
        print('ПОМИЛКА ' + п, file=sys.stderr)
    sys.exit(1 if помилки else 0)
