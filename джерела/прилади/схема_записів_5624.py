"""Лічильник класу 5624 (дві схеми записів): кожен запис застосованого каталогу проти схеми v1.

Запуск з кореня репозиторію: `python3 джерела/прилади/схема_записів_5624.py [--фід] [каталог_записи_v1.jsonl.gz]`.
Види (друкує число за кожним і разом; код ≠ 0, коли разом > 0):
  поза_схемою      — поле першого рівня поза `складальник.ПОЛЯ_ЗАПИСУ` (як `ціна_стара` замість `стара_ціна`);
  без_значення     — обов'язкове поле порожнє; з `--фід` ще слот «комплект» без типу у читача фіда (`feed.прогін`, ~2 хв);
  двійники         — повтор `ід` чи точної адреси, мовна версія (`/ru/`, `/en/`) при українській сестрі;
  адреси_фото      — кадр не абсолютний `http(s)://`, з пробілом чи з `<base href>`-шляхом 25union (`/katalog/…/image/cache/`);
  стара_ціна       — запис із `стара_ціна`, чий `<oldprice>` у XML відсутній чи інший, або стара не більша за ціну."""
import collections
import os
import re
import sys
import tempfile
import xml.etree.ElementTree as ET

КОРІНЬ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
sys.path.insert(0, os.path.join(КОРІНЬ, "zhnyvarka"))
import складальник as с  # noqa: E402
from жнива_каталог import адреса, чужа_мова  # noqa: E402

ВИДИ = ("поза_схемою", "без_значення", "двійники", "адреси_фото", "стара_ціна")
_ХИБНИЙ_КАДР = re.compile(r"^https?://[^/]+/katalog/.*?/image/cache/")


def порахувати(записи):
    """Повертає {вид: кількість місць} і по три приклади (ід) на вид."""
    лічба, приклади = collections.Counter(), collections.defaultdict(list)

    def знайдено(вид, запис):
        лічба[вид] += 1
        if len(приклади[вид]) < 3:
            приклади[вид].append(запис.get("ід"))

    за_ід = collections.Counter(з.get("ід") for з in записи)
    за_url = collections.Counter(з.get("адреса") for з in записи)
    українські = {адреса(з["адреса"]) for з in записи if з.get("адреса") and not чужа_мова(з["адреса"])}
    for з in записи:
        for _ in set(з) - с.ПОЛЯ_ЗАПИСУ:
            знайдено("поза_схемою", з)
        for поле in с.ПОЛЯ_ОБОВ:
            if з.get(поле) in (None, "", [], {}):
                знайдено("без_значення", з)
        if за_ід[з.get("ід")] > 1 or за_url[з.get("адреса")] > 1 or (
                з.get("адреса") and чужа_мова(з["адреса"]) and адреса(з["адреса"]) in українські):
            знайдено("двійники", з)
        for кадр in з.get("кадри") or []:
            if not кадр.startswith(("http://", "https://")) or re.search(r"\s", кадр) or _ХИБНИЙ_КАДР.match(кадр):
                знайдено("адреси_фото", з)
        стара = з.get("стара_ціна")
        if стара:
            try:
                ціна = ET.fromstring(с.офер_xml(з)).findtext("oldprice")
                вада = ціна is None or float(ціна) != float(стара) or float(стара) <= float(з["ціна"])
            except (TypeError, ValueError, ET.ParseError):
                вада = True
            if вада:
                знайдено("стара_ціна", з)
    return лічба, приклади


def комплекти_без_типу():
    """Записи слота «комплект» без типу в образі, який читає фід (тип — не поле запису, його дає читач виду)."""
    sys.path.insert(0, os.path.join(КОРІНЬ, "джерела"))
    import feed
    каталог = feed.прогін(feed.каталог_на_диску(), [], кеш=os.path.join(tempfile.gettempdir(), "_5624_кеш.json"),
                          ліміт_фото=0)["каталог"]
    return [x["id"] for x in каталог if x["слот"] == "комплект" and not x.get("тип")]


def main(аргументи):
    з_фідом = "--фід" in аргументи
    шляхи = [а for а in аргументи if а != "--фід"]
    _, записи = с.читати_записи(шляхи[0] if шляхи else с.ЗАПИСИ)
    лічба, приклади = порахувати(записи)
    if з_фідом:
        ід = комплекти_без_типу()
        лічба["без_значення"] += len(ід)
        приклади["без_значення"] += ід[:3]
    for вид in ВИДИ:
        print("%-12s %6d  %s" % (вид, лічба[вид], приклади[вид]))
    разом = sum(лічба[в] for в in ВИДИ)
    print("разом", разом, "з записів", len(записи))
    return 1 if разом else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
