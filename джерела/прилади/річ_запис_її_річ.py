"""П.4 кореня Річ-запис-речі для ЇЇ речі — від виконання на записаних відповідях моделей.

Клас (паспорт, рішення 08.11): запис — і її річ від відповіді мовного шару чи моделі зору до картки; місце п.4 —
текст поля її запису взято не з поля цієї речі у відповіді моделі, а з ширшого тексту: уривка її речення (`quote`)
чи її репліки. Чия річ і закріплення — поза класом.

Запуск з кореня: python джерела/прилади/річ_запис_її_річ.py [--json | --відбитки]; число кореня друкує
`корінь_річ_запис_речі.py` (один `прилад:` на паспорт) разом з місцями сторінок крамниць.

Як лічить. Записані відповіді нічного прогону 07.11 (`VIDPOVIDI` сцен) проходять тим самим кодом продукту, що в
показі: хід розмови — `мовний_шар.прийняти_розмову` / `прийняти_хід_плиток` → `паспорт_з_шару` (там
`річ_з_фото.її_речі_шару` і `речі_з_json`), фото — `річ_з_фото.речі_з_відповіді_фото`; запис → картка —
`річ_з_фото.картки_з_паспорта` (`запис_каталогу`, `картка`). Код продукту не змінено й не позначено.
Порушення — рядок запису чи картки її речі, рівний (після стискання пробілів) уривку чи репліці цієї відповіді й не
рівний жодному іншому рядку відповіді (полю речі: `name`, `free_text`…). Місце — `файл:рядок` коду продукту, де цей
текст став полем запису: трасування (`sys.settrace`) кадрів коду продукту; перший за поверненням кадр, що віддав той
самий рядковий об'єкт під ключем поля (`назва`), а на вході під цим ключем його не мав, — рядок, де локальна стала
ним. Читачі запису далі (паспорт, картка) мають його на вході під тим самим ключем і місцем не стають.
"""
import hashlib
import json
from pathlib import Path
import re
import sys

ТЕКИ = (Path('аудит/проби/Е1-нічний-живий-20261107'), Path('аудит/проби/нічні/20261107'))
ВІДБИТКИ = Path(__file__).resolve().parent / 'річ_запис_дані' / 'її_річ_відбитки.json'
_ЗАПИС = re.compile(r"── ПРОМПТ \(\d+ симв\.\) ──\n(.*)\n\n── ВІДПОВІДЬ \(([^\n]*)\) ──\n(.*)\n$", re.S)
_ВИДИ = (('_хід_розмови', 'розмова'), ('_хід_плиток', 'плитки'), ('_речі_з_фото_шар', 'фото'))


def входи(корінь):
    """[(шлях від кореня, вид)] — записи ходу розмови, ходу плиток і речей з фото, у сталому порядку."""
    вих = []
    for тека in ТЕКИ:
        for ф in sorted((корінь / тека).glob('*/VIDPOVIDI/*.txt')):
            вид = next((в for мітка, в in _ВИДИ if мітка in ф.name), None)
            if вид:
                вих.append((ф.relative_to(корінь).as_posix(), вид))
    return вих


def відбитки(корінь, файли):
    """{шлях: sha256} входів."""
    return {ш: hashlib.sha256((корінь / ш).read_bytes()).hexdigest() for ш, _ in файли}


def звірити(корінь, файли):
    """Змінений, зниклий чи новий вхід — помилка, а не тихо менше місць."""
    маніфест = json.loads(ВІДБИТКИ.read_text(encoding='utf-8'))
    if маніфест != відбитки(корінь, файли):
        raise ValueError('входи її речі не збігаються з річ_запис_дані/її_річ_відбитки.json')


def н(т):
    """Рядок для звірки: пробіли стиснено, регістр знято."""
    return ' '.join(str(т).split()).casefold()


def рядки(зн, ключ=None):
    """[(ключ, рядок)] усіх рядкових листків JSON."""
    if isinstance(зн, dict):
        return [п for к, з in зн.items() for п in рядки(з, к)]
    if isinstance(зн, list):
        return [п for з in зн for п in рядки(з, ключ)]
    return [(ключ, зн)] if isinstance(зн, str) and зн.strip() else []


def обʼєкт(т):
    """Перший JSON-об'єкт тексту відповіді чи промпту (огорожу ```json знято)."""
    т = re.sub(r'^\s*```(?:json)?\s*|\s*```\s*$', '', т.strip())
    try:
        return json.loads(т)
    except ValueError:
        м = re.search(r'\{.*\}', т, re.S)
        try:
            return json.loads(м.group(0)) if м else None
        except ValueError:
            return None


def листки(зн, ключ=None, межа=4000):
    """[(ключ, рядок)] рядкових листків об'єкта (ті самі об'єкти, не копії), до `межа` вузлів."""
    вих, стек, бачено = [], [(ключ, зн, 0)], 0
    while стек and бачено < межа:
        к, з, глиб = стек.pop()
        бачено += 1
        if isinstance(з, str):
            вих.append((к, з))
        elif глиб < 8 and isinstance(з, dict):
            стек.extend((кк, зз, глиб + 1) for кк, зз in з.items())
        elif глиб < 8 and isinstance(з, (list, tuple)):
            стек.extend((к, зз, глиб + 1) for зз in з)
    return вих


class Трасування:
    """Кадри коду продукту: рядкові листки входу й виходу кадру та рядки, де локальна стала рядком."""

    def __init__(self, джерела):
        """`джерела` — тека коду продукту; прилади, проби й тести — поза нею."""
        self.джерела, self.кадри, self.готові = str(джерела) + '/', {}, []

    def свій(self, кадр):
        """Кадр коду продукту, не приладу."""
        ф = кадр.f_code.co_filename
        return ф.startswith(self.джерела) and '/прилади/' not in ф and '/проби/' not in ф

    def __call__(self, кадр, подія, арг):
        """Глобальний трасувальник: лише кадри продукту."""
        if подія != 'call' or not self.свій(кадр):
            return None
        вхід = листки(dict(кадр.f_locals))
        self.кадри[id(кадр)] = dict(вхід=вхід, попередній=кадр.f_lineno, бачені={}, події=[])
        return self.місцевий

    def місцевий(self, кадр, подія, арг):
        """Після кожного рядка — нові рядкові локальні (рядок і об'єкт); при поверненні — листки виходу."""
        стан = self.кадри.get(id(кадр))
        if стан is None:
            return None
        if подія in ('line', 'return'):
            for к, з in list(кадр.f_locals.items()):
                if isinstance(з, str) and стан['бачені'].get(к) is not з:
                    стан['бачені'][к] = з
                    стан['події'].append((стан['попередній'], з))
            стан['попередній'] = кадр.f_lineno
        if подія == 'return':
            self.кадри.pop(id(кадр), None)
            self.готові.append(dict(файл=кадр.f_code.co_filename, рядок=кадр.f_lineno, вхід=стан['вхід'],
                                    вихід=листки(арг), події=стан['події']))
        return self.місцевий

    def місце(self, ключ, обʼєкт):
        """(файл, рядок), де рядок `обʼєкт` уперше став полем `ключ`: перший за поверненням кадр, що віддав його під
        цим ключем, а на вході під цим ключем не мав (сам рядок — той самий об'єкт, що й `quote` розібраної відповіді,
        тож «не мав на вході» — саме під ключем поля); рядок — де локальна стала ним, інакше рядок повернення."""
        for к in self.готові:
            if any(о is обʼєкт and кл == ключ for кл, о in к['вихід']) and \
                    not any(о is обʼєкт and кл == ключ for кл, о in к['вхід']):
                рядки_ = [р for р, о in к['події'] if о is обʼєкт]
                return к['файл'], (рядки_[-1] if рядки_ else к['рядок'])
        return None


def прогнати(корінь, шлях, вид, модулі, слід):
    """Виконує код продукту над одним записом; повертає (записи й картки її речі, ширші тексти, поля речі)."""
    М, РФ = модулі
    т = (корінь / шлях).read_text(encoding='utf-8', errors='replace')
    г = _ЗАПИС.match(т)
    if not г or 'HTTP 200' not in г.group(2):
        return [], set(), set()
    промпт, відповідь = г.group(1), г.group(3)
    сира = обʼєкт(відповідь) or {}
    пр = обʼєкт(промпт) if промпт.lstrip().startswith('{') else None
    слова = пр.get('her_new_message') if isinstance(пр, dict) else None
    слова = слова if isinstance(слова, str) else ''
    ширші = {н(з) for к, з in рядки(сира) if к == 'quote'} | ({н(слова)} if слова.strip() else set())
    поля = {н(з) for к, з in рядки(сира) if к != 'quote'}
    sys.settrace(слід)
    try:
        if вид == 'фото':
            фото = sorted({str(о.get('photo')) for о in (сира.get('items') or []) if isinstance(о, dict) and о.get('photo')})
            власні = (пр or {}).get('her_items_in_words') if isinstance(пр, dict) else None
            р = РФ.речі_з_відповіді_фото(відповідь, [{'ід': ф, 'ширина': 1000, 'висота': 1600} for ф in фото],
                                         власні=власні if isinstance(власні, list) else None)
            паспорт = {'речі_з_фото': р['речі_з_фото']}
        else:
            р = (М.прийняти_хід_плиток if вид == 'плитки' else М.прийняти_розмову)(відповідь)
            паспорт = М.паспорт_з_шару(р.get('внутрішня') or {}, {}, слова_ходу=слова)['паспорт']
        речі = [р_ for р_ in (паспорт.get('речі_з_фото') or []) if isinstance(р_, dict)]
        картки = list(РФ.картки_з_паспорта({'речі_з_фото': речі}).values())
    finally:
        sys.settrace(None)
    return речі + картки, ширші, поля


def лічити(корінь, джерела=None):
    """[{файл, рядок, поле, значення, вхід}] — місця п.4 її речі; помилка входу чи коду — виняток, не нуль."""
    корінь = Path(корінь).resolve()
    джерела = Path(джерела or корінь / 'джерела').resolve()
    файли = входи(корінь)
    звірити(корінь, файли)
    sys.path.insert(0, str(джерела))
    import мовний_шар as М
    import річ_з_фото as РФ
    вих, бачено = [], set()
    for шлях, вид in файли:
        слід = Трасування(джерела)
        записи, ширші, поля = прогнати(корінь, шлях, вид, (М, РФ), слід)
        for запис in записи:
            for ключ, значення in рядки(запис):
                if н(значення) not in ширші or н(значення) in поля:
                    continue
                місце = слід.місце(ключ, значення)
                if not місце:
                    raise AssertionError(f'{шлях}: «{значення}» у записі без кадру, що його записав, — трасування неповне')
                файл, рядок = місце
                if (шлях, файл, рядок, ключ, значення) in бачено:
                    continue
                бачено.add((шлях, файл, рядок, ключ, значення))
                вих.append(dict(файл=Path(файл).relative_to(корінь).as_posix(), рядок=рядок, поле=ключ,
                                значення=значення, вхід=шлях))
    return вих


