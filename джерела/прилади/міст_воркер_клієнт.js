/* Клієнт моста до `міст_воркер.js` (прототип кроку 4.1): той самий контракт, що `містП(ім, дані)` у показі —
   проміс розібраної відповіді, — плюс покоління входу (рядок дошки 7311).

   ПОКОЛІННЯ. Виклик із `ключем` («палітри», «вибір_палітри»…) робить попередні виклики з тим самим ключем застарілими.
   Відповідь несе `пок` свого входу; застаріла відкидається: проміс відхиляється помилкою з `застаріло: true`, і
   продовження викликача (запис `ПАЛІТРА`, DOM, нот) не виконується. Доти `оновитиПалітруП` писала після `await` без
   звірки: зміна чипа чи сценарію, поки міст рахував стару палітру, давала змішаний стан (7311). Для записів після
   ДРУГОГО очікування (модель, мовний шар) викликач звіряє `чинне(ключ, пок)` сам — `пок` повертає `покоління(ключ)`.

   Без ключа виклик ніщо не відміняє (`мова`, `вердикт`, руки збору — кожен вхід свій), але `н` і `пок` теж несе:
   відповіді `виклик_а` можуть приходити не в порядку відправлення. */
function створитиМістВоркера(воркер){
  let н = 0, пок = 0;
  const чекають = new Map();        // н → {ім, ключ, пок, т0, байтів, сирий, прийняти, відхилити}
  const останнє = new Map();        // ключ → пок останнього входу
  const журнал = [];                // {н, ім, пок, мс_python, мс_обіг, мс_розбір, байтів_входу, байтів_виходу, застаріло}

  воркер.addEventListener('message', е => {
    const в = е.data;
    if (в.тип !== 'відповідь') return;
    const ч = чекають.get(в.н);
    if (!ч) return;
    чекають.delete(в.н);
    const запис = {н: в.н, ім: ч.ім, пок: в.пок, мс_python: в.мс_python, мс_обіг: performance.now() - ч.т0,
                   байтів_входу: ч.байтів, байтів_виходу: в.вих ? в.вих.length : 0};
    журнал.push(запис);
    if (ч.ключ != null && останнє.get(ч.ключ) !== в.пок){
      запис.застаріло = true;
      const п = new Error('stale_bridge_answer: ' + ч.ключ);
      п.застаріло = true;
      return ч.відхилити(п);
    }
    if (в.помилка != null) return ч.відхилити(new Error(в.помилка));
    const т = performance.now();
    const р = JSON.parse(в.вих);
    запис.мс_розбір = performance.now() - т;
    ч.прийняти(ч.сирий ? в.вих : р);
  });

  /* `сирий: true` — віддати рядок відповіді без розбору (прилад порівнює рядки байт у байт) */
  function виклик(ім, дані, {ключ = null, асинх = null, сирий = false} = {}){
    const вхід = JSON.stringify(дані === undefined ? null : дані);
    const мій = ++пок, номер = ++н;
    if (ключ != null) останнє.set(ключ, мій);
    /* `поступливий` — те саме правило, що в `показ.html: містП`: «суд» і «каталог» оцінки йдуть `bridge.виклик_а` */
    const а = асинх != null ? асинх : (ім === 'оцінка' && !!дані && (дані.крок === 'суд' || дані.крок === 'каталог'));
    return new Promise((прийняти, відхилити) => {
      чекають.set(номер, {ім, ключ, пок: мій, т0: performance.now(), байтів: вхід.length, сирий, прийняти, відхилити});
      воркер.postMessage({тип: 'виклик', н: номер, пок: мій, ім, вхід, асинх: а});
    });
  }

  return {
    виклик,
    покоління: ключ => останнє.get(ключ),
    чинне: (ключ, п) => останнє.get(ключ) === п,
    журнал,
  };
}

if (typeof module !== 'undefined') module.exports = {створитиМістВоркера};
