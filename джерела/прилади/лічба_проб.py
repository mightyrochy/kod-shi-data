# -*- coding: utf-8 -*-
"""ЛІЧБА ПРОБ: скільки проб у репозиторії, скільки з них зелені й які червоні.

ЩО ЦЕ ЛАГОДИТЬ (рядок 173 дошки, знахідка CI-3/#414). Проб у репозиторії 558
(`джерела/проби/*.py` і `аудит/проби/*.py`), а прогоном покриті були рівно 14
(`проби/поділ_*_ast.py` у `zbirka.yml`) плюс кілька приладів батареї. Скільки
червоних серед решти — не знав НІХТО: дізнатись можна було тільки прогоном
кожної руками. Проба, яку ніхто не переміряє, — це вже не вимір, а запис про
вимір: докстрінг каже «факт», а факт міг змінитись три хвилі тому.

ЦЕ НЕ ГЕЙТ (CLAUDE.md п.3). Типово прилад друкує звіт і виходить 0 — навіть
коли червоні є: рядок 173 просить саме звіт, а не блокування на кожну помилку.
`--гейт` (для того, хто сам захотів двійкового коду) виходить 1 при червоних.
У CI приладу свідомо НЕ додано.

ПРОГІН (з теки `джерела`, каталоги мусять бути розпаковані й почищені —
`python3 -c "import чистка_каталогу as ч; ч.забезпечити_чистим('каталог_повний.xml')"`):
    python3 прилади/лічба_проб.py                 # усе, крім переліку «окремо»
    python3 прилади/лічба_проб.py --окремо        # і «окремо» теж (довго, мережа)
    python3 прилади/лічба_проб.py --лише проби/chyp_simji.py проби/bas_ochi_81.py
    python3 прилади/лічба_проб.py --гейт          # rc 1, коли червоні є
env: NYTOK (ниток, типово 4), STELYA (стеля секунд на пробу, типово 120),
     ZVIT (файл JSONL: рядок на пробу, дописується на ходу — прогін, що вмер
     на ліміті чи на пам'яті, не губить уже зміряного).
Імена env ЛАТИНИЦЕЮ: оболонка кириличних не має (той самий урок, що в
`zbirka.yml` про `LYUSTERKO_CATALOG` і в `рв6_стенд.js` про `ZNIMKY`).

ЧОМУ ПЕРЕЛІК «ОКРЕМО» ЛЕЖИТЬ ФАЙЛОМ, А НЕ ЗДОГАДОМ. Проба, якій потрібні
мережа до крамниць, браузер, ноутбук із моделлю чи аргумент, з голого прогону
червоніє не поломкою продукту, а браком входу — і така «червона» ховає
справжні. Тому кожна така проба названа в `лічба_проб_окремо.json` РАЗОМ ІЗ
ПРИЧИНОЮ і показана окремим переліком; здогадів про «повільність» прилад не
робить. Рядок реєстру, що вказує на пробу, якої вже нема, прилад називає
голосно: інакше реєстр тихо росте й починає ховати живі проби.
"""
import sys, os, json, time, glob, subprocess, argparse
import concurrent.futures as cf

_ТУТ = os.path.dirname(os.path.abspath(__file__))
ДЖЕРЕЛА = os.path.dirname(_ТУТ)
КОРІНЬ = os.path.dirname(ДЖЕРЕЛА)
РЕЄСТР = os.path.join(_ТУТ, 'лічба_проб_окремо.json')


def знайти_проби():
    """Усі проби — як шлях від кореня репозиторію, у сталому порядку."""
    п = ['джерела/проби/' + os.path.basename(x)
         for x in sorted(glob.glob(os.path.join(ДЖЕРЕЛА, 'проби', '*.py')))]
    п += ['аудит/проби/' + os.path.basename(x)
          for x in sorted(glob.glob(os.path.join(КОРІНЬ, 'аудит', 'проби', '*.py')))]
    return п


def читати_реєстр():
    """{шлях: причина} для проб, які з голого прогону не міряють продукт."""
    with open(РЕЄСТР, encoding='utf-8') as ф:
        д = json.load(ф)
    return {к: v for к, v in д.items() if not к.startswith('_')}


def гнати(шлях, стеля):
    """Одна проба підпроцесом. CWD — той, з якого її запускає її ж докстрінг:
    `джерела` для `джерела/проби/*`, корінь репозиторію для `аудит/проби/*`."""
    у_джерелах = шлях.startswith('джерела/')
    cwd = ДЖЕРЕЛА if у_джерелах else КОРІНЬ
    арг = шлях[len('джерела/'):] if у_джерелах else шлях
    почато = time.time()
    # stdin закритий: проба, що чекає на введення, має впасти, а не повісити прогін.
    try:
        р = subprocess.run([sys.executable, арг], cwd=cwd, stdin=subprocess.DEVNULL,
                           capture_output=True, text=True, errors='replace',
                           timeout=стеля, env=dict(os.environ, PYTHONIOENCODING='utf-8'))
        rc, вивід, помилки = р.returncode, р.stdout, р.stderr
    except subprocess.TimeoutExpired:
        rc, вивід, помилки = 124, '', 'СТЕЛЯ ЧАСУ %d с' % стеля
    хвіст = [x for x in (помилки or '').splitlines() if x.strip()]
    return {'проба': шлях, 'rc': rc, 'сек': round(time.time() - почато, 1),
            'рядків_виводу': len((вивід or '').splitlines()),
            'причина': хвіст[-1][:300] if хвіст else ''}


def друкувати(звіти, окремо, зайві):
    зелені = [z for z in звіти if z['rc'] == 0]
    червоні = [z for z in звіти if z['rc'] != 0]
    print('\nпроб %d · зелених %d · червоних %d · окремо %d'
          % (len(звіти) + len(окремо), len(зелені), len(червоні), len(окремо)))
    if червоні:
        print('\nЧЕРВОНІ (%d):' % len(червоні))
        for z in sorted(червоні, key=lambda z: z['проба']):
            print('  ✗ %-52s rc %-4s %6.1f с  %s'
                  % (z['проба'], z['rc'], z['сек'], z['причина']))
    if окремо:
        print('\nОКРЕМО — не міряють продукт із голого прогону (%d):' % len(окремо))
        for шлях, причина in sorted(окремо.items()):
            print('  · %-52s %s' % (шлях, причина))
    if зайві:
        print('\nРЕЄСТР ВІДСТАВ — цих проб уже нема (%d): %s' % (len(зайві), ', '.join(sorted(зайві))))
    повільні = sorted(звіти, key=lambda z: -z['сек'])[:10]
    if повільні:
        print('\nНАЙПОВІЛЬНІШІ 10: ' + ' · '.join('%s %.0f с' % (z['проба'].split('/')[-1], z['сек'])
                                                  for z in повільні))
    print('усього часу на проби: %.0f с' % sum(z['сек'] for z in звіти))
    return len(червоні)


def main():
    р = argparse.ArgumentParser(add_help=True)
    р.add_argument('--окремо', action='store_true', help='гнати й проби з реєстру «окремо»')
    р.add_argument('--гейт', action='store_true', help='rc 1, коли червоні є')
    р.add_argument('--лише', nargs='+', default=None, help='лише названі проби')
    а = р.parse_args()

    усі, реєстр = знайти_проби(), читати_реєстр()
    зайві = set(реєстр) - set(усі)
    if а.лише:
        черга, окремо = [x for x in усі if x in set(а.лише)], {}
        бракує = set(а.лише) - set(черга)
        if бракує:
            print('НЕ ПРОБИ (нема серед знайдених): %s' % ', '.join(sorted(бракує)))
    elif а.окремо:
        черга, окремо = усі, {}
    else:
        черга = [x for x in усі if x not in реєстр]
        окремо = {к: v for к, v in реєстр.items() if к in set(усі)}

    ниток, стеля = int(os.environ.get('NYTOK', '4')), int(os.environ.get('STELYA', '120'))
    print('проб знайдено %d · у черзі %d · ниток %d · стеля %d с' % (len(усі), len(черга), ниток, стеля))
    звіт_файл = open(os.environ['ZVIT'], 'w', encoding='utf-8') if os.environ.get('ZVIT') else None
    звіти = []
    with cf.ThreadPoolExecutor(max_workers=ниток) as пул:
        for готово, z in enumerate(пул.map(lambda ш: гнати(ш, стеля), черга), 1):
            звіти.append(z)
            if звіт_файл:
                звіт_файл.write(json.dumps(z, ensure_ascii=False) + '\n')
                звіт_файл.flush()
            if z['rc'] != 0:
                print('  ✗ %s rc %s (%.0f с)' % (z['проба'], z['rc'], z['сек']), flush=True)
            elif готово % 50 == 0:
                print('  … %d / %d' % (готово, len(черга)), flush=True)
    if звіт_файл:
        звіт_файл.close()
    червоних = друкувати(звіти, окремо, зайві)
    return 1 if (а.гейт and червоних) else 0


if __name__ == '__main__':
    sys.exit(main())
