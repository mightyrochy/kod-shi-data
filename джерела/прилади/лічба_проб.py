import sys, os, json, time, glob, subprocess, argparse, hashlib, shutil, tempfile, threading
import concurrent.futures as cf

_ТУТ = os.path.dirname(os.path.abspath(__file__))
ДЖЕРЕЛА = os.path.dirname(_ТУТ)
КОРІНЬ = os.path.dirname(ДЖЕРЕЛА)
РЕЄСТР = os.path.join(_ТУТ, 'лічба_проб_окремо.json')
КОД_БЕЗ_ВХОДУ = 77   # той самий, що SKIP у automake/ctest: «не виконувалось», не «пройдено»


def стан(z):
    """'червона' | 'без входу' | 'зелена' — дерево, змінене пробою, робить її червоною за будь-якого rc."""
    if z.get('дерево'):
        return 'червона'
    if z['rc'] == КОД_БЕЗ_ВХОДУ:
        return 'без входу'
    return 'зелена' if z['rc'] == 0 else 'червона'


class Дерево:
    """Знімок робочого дерева й повернення до нього (Д11).

    Знімок — `git status --porcelain -z -uall`: шлях → код стану. Шлях, брудний
    ДО прогону (правка сесії, що жене прилад), ще й копіюється вбік із sha256 —
    інакше проба, що дописала в уже змінений файл, лишилась би непоміченою, а
    повернення затерло б чужу правку."""

    def __init__(self):
        self.копії = tempfile.mkdtemp(prefix='лічба_дерево_')
        self.база = self._статус()
        self.хеш = {}
        for ш in self.база:
            п = os.path.join(КОРІНЬ, ш)
            if os.path.isfile(п):
                ціль = os.path.join(self.копії, hashlib.sha256(ш.encode()).hexdigest())
                shutil.copy2(п, ціль)
                self.хеш[ш] = self._sha(п)
        self.замок = threading.Lock()

    @staticmethod
    def _sha(п):
        h = hashlib.sha256()
        with open(п, 'rb') as ф:
            for шм in iter(lambda: ф.read(1 << 20), b''):
                h.update(шм)
        return h.hexdigest()

    @staticmethod
    def _статус():
        р = subprocess.run(['git', '--no-optional-locks', '-c', 'core.quotepath=off', 'status', '--porcelain=v1', '-z',
                            '--untracked-files=all'], cwd=КОРІНЬ, capture_output=True, check=True)
        поля, д, і = р.stdout.decode('utf-8', 'surrogateescape').split('\0'), {}, 0
        while і < len(поля):
            запис = поля[і]
            і += 1
            if len(запис) < 4:
                continue
            д[запис[3:]] = запис[:2]
            if запис[0] in 'RC':   # перейменування: наступне поле — старий шлях
                і += 1
        return д

    def зміни(self):
        """Шляхи, що відрізняються від знімка, у сталому порядку."""
        тепер, з = self._статус(), set()
        for ш, код in тепер.items():
            if self.база.get(ш) != код:
                з.add(ш)
            elif ш in self.хеш:
                п = os.path.join(КОРІНЬ, ш)
                if not os.path.isfile(п) or self._sha(п) != self.хеш[ш]:
                    з.add(ш)
        з |= {ш for ш in self.база if ш not in тепер}
        return sorted(з)

    def повернути(self, шляхи):
        """Кожен шлях — у стан знімка."""
        for ш in шляхи:
            п = os.path.join(КОРІНЬ, ш)
            if ш in self.хеш:
                os.makedirs(os.path.dirname(п), exist_ok=True)
                shutil.copy2(os.path.join(self.копії, hashlib.sha256(ш.encode()).hexdigest()), п)
            elif ш in self.база:            # видалений до прогону, а проба створила знову
                if os.path.isfile(п):
                    os.remove(п)
            elif subprocess.run(['git', 'cat-file', '-e', 'HEAD:' + ш], cwd=КОРІНЬ,
                                capture_output=True).returncode == 0:
                subprocess.run(['git', 'checkout', 'HEAD', '--', ш], cwd=КОРІНЬ,
                               capture_output=True, check=True)
            elif os.path.lexists(п):        # новий файл проби
                os.remove(п)
                тека = os.path.dirname(п)
                while тека != КОРІНЬ and os.path.isdir(тека) and not os.listdir(тека):
                    os.rmdir(тека)
                    тека = os.path.dirname(тека)

    def прибрати(self):
        shutil.rmtree(self.копії, ignore_errors=True)


def знайти_проби():
    """Усі проби — як шлях від кореня репозиторію, у сталому порядку."""
    п = ['джерела/проби/' + os.path.basename(x)
         for x in sorted(glob.glob(os.path.join(ДЖЕРЕЛА, 'проби', '*.py')))]
    п += ['аудит/проби/' + os.path.basename(x)
          for x in sorted(glob.glob(os.path.join(КОРІНЬ, 'аудит', 'проби', '*.py')))]
    return п


def читати_реєстр():
    """{шлях: причина} для проб, які з голого прогону не міряють продукт."""
    with open(РЕЄСТР, encoding='utf-8') as ф:
        д = json.load(ф)
    return {к: v for к, v in д.items() if not к.startswith('_')}


_ЗВІДКИ_ДЖЕРЕЛА = ('з теки `джерела`', 'із теки `джерела`', 'з теки джерела',
                   'cd джерела', 'Запуск із `джерела`')


def тека_прогону(шлях):
    """Тека, з якої проба просить себе запускати — її ж словами.

    Типово: `джерела` для `джерела/проби/*`, корінь репозиторію для `аудит/проби/*`.
    АЛЕ ЧАСТИНА ПРОБ `аудит/проби/` КАЖЕ ІНШЕ: `рв4_поломка_у_пакеті.py` і
    `рв4_питання_без_адресата.py` несуть у докстрінгу «Запуск із теки `джерела`:
    python3 ../аудит/проби/…» і читають `стенд_вх.json` поруч. З кореня вони падали
    `FileNotFoundError` — тобто прилад міряв би власний здогад про теку, а не пробу.
    Тому тека береться з ДОКСТРІНГА, коли він її називає; здогадів прилад не робить.
    """
    типова = ДЖЕРЕЛА if шлях.startswith('джерела/') else КОРІНЬ
    повний = os.path.join(КОРІНЬ, шлях)
    try:
        with open(повний, encoding='utf-8', errors='replace') as ф:
            шапка = ''.join(ф.readline() for _ in range(40))
    except OSError:
        return типова
    return ДЖЕРЕЛА if any(м in шапка for м in _ЗВІДКИ_ДЖЕРЕЛА) else типова


def гнати(шлях, стеля):
    """Одна проба підпроцесом, з теки, яку називає її власний докстрінг."""
    cwd = тека_прогону(шлях)
    арг = os.path.relpath(os.path.join(КОРІНЬ, шлях), cwd)
    почато = time.time()
    # PYTHONPATH = `джерела` + корінь, БО ТАК КАЖУТЬ САМІ ПРОБИ. 41 проба з 516 у
    # `джерела/проби/` документує прогін рядком `PYTHONPATH=. python3 проби/…`
    # (решта кладе корінь у `sys.path` сама), а проби з `аудит/проби/` ходять від
    # кореня репозиторію, але імпортують модулі з `джерела` — і `bridge`, `outfit`,
    # `мовний_шар` там не знаходяться інакше. Без цього прилад називав би їх
    # червоними за `ModuleNotFoundError: No module named 'bridge'` — тобто міряв би
    # власний спосіб запуску, а не проби. Код у репозиторії має ОДИН корінь
    # (`джерела`), тож дати його кожній пробі і означає запустити її «як
    # документовано». Що проба кладе в `sys.path` сама — лишається як було.
    # stdin закритий: проба, що чекає на введення, має впасти, а не повісити прогін.
    try:
        р = subprocess.run([sys.executable, арг], cwd=cwd, stdin=subprocess.DEVNULL,
                           capture_output=True, text=True, errors='replace',
                           timeout=стеля, env=dict(os.environ, PYTHONIOENCODING='utf-8',
                                                  PYTHONPATH=ДЖЕРЕЛА + os.pathsep + КОРІНЬ))
        rc, вивід, помилки = р.returncode, р.stdout, р.stderr
    except subprocess.TimeoutExpired:
        rc, вивід, помилки = 124, '', 'СТЕЛЯ ЧАСУ %d с' % стеля
    хвіст = [x for x in (помилки or '').splitlines() if x.strip()]
    if rc == КОД_БЕЗ_ВХОДУ:      # чого бракує, проба каже у виводі, а не в stderr
        хвіст = [x for x in (вивід or '').splitlines() if x.strip()] or хвіст
    return {'проба': шлях, 'rc': rc, 'сек': round(time.time() - почато, 1),
            'рядків_виводу': len((вивід or '').splitlines()),
            'причина': хвіст[-1][:300] if хвіст else ''}


def друкувати(звіти, окремо, зайві, брудне_наприкінці):
    зелені = [z for z in звіти if стан(z) == 'зелена']
    червоні = [z for z in звіти if стан(z) == 'червона']
    без_входу = [z for z in звіти if стан(z) == 'без входу']
    print('\nпроб %d · зелених %d · червоних %d · без входу %d · окремо %d · писали в дерево %d'
          % (len(звіти) + len(окремо), len(зелені), len(червоні), len(без_входу), len(окремо),
             sum(1 for z in звіти if z.get('дерево'))))
    if червоні:
        print('\nЧЕРВОНІ (%d):' % len(червоні))
        for z in sorted(червоні, key=lambda z: z['проба']):
            print('  ✗ %-52s rc %-4s %6.1f с  %s'
                  % (z['проба'], z['rc'], z['сек'], z['причина']))
            if z.get('дерево'):
                print('      ДЕРЕВО ЗМІНЕНО (повернуто): %s' % ', '.join(z['дерево']))
    if без_входу:
        print('\nБЕЗ ВХОДУ — не виконувались, бо нема входу; не провал і не успіх (%d):' % len(без_входу))
        for z in sorted(без_входу, key=lambda z: z['проба']):
            print('  ~ %-52s %s' % (z['проба'], z['причина']))
    if окремо:
        print('\nОКРЕМО — не міряють продукт із голого прогону (%d):' % len(окремо))
        for шлях, причина in sorted(окремо.items()):
            print('  · %-52s %s' % (шлях, причина))
    if зайві:
        print('\nРЕЄСТР ВІДСТАВ — цих проб уже нема (%d): %s' % (len(зайві), ', '.join(sorted(зайві))))
    повільні = sorted(звіти, key=lambda z: -z['сек'])[:10]
    if повільні:
        print('\nНАЙПОВІЛЬНІШІ 10: ' + ' · '.join('%s %.0f с' % (z['проба'].split('/')[-1], z['сек'])
                                                  for z in повільні))
    print('усього часу на проби: %.0f с' % sum(z['сек'] for z in звіти))
    print('дерево після прогону: %s' % ('ЧИСТЕ (як до прогону)' if not брудне_наприкінці else
                                        'НЕ ПОВЕРНУТО: ' + ', '.join(брудне_наприкінці)))
    return len(червоні)


def main():
    р = argparse.ArgumentParser(add_help=True)
    р.add_argument('--окремо', action='store_true', help='гнати й проби з реєстру «окремо»')
    р.add_argument('--гейт', action='store_true', help='rc 1, коли червоні є')
    р.add_argument('--лише', nargs='+', default=None, help='лише названі проби')
    а = р.parse_args()

    усі, реєстр = знайти_проби(), читати_реєстр()
    зайві = set(реєстр) - set(усі)
    if а.лише:
        черга, окремо = [x for x in усі if x in set(а.лише)], {}
        бракує = set(а.лише) - set(черга)
        if бракує:
            print('НЕ ПРОБИ (нема серед знайдених): %s' % ', '.join(sorted(бракує)))
    elif а.окремо:
        черга, окремо = усі, {}
    else:
        черга = [x for x in усі if x not in реєстр]
        окремо = {к: v for к, v in реєстр.items() if к in set(усі)}

    ниток, стеля = int(os.environ.get('NYTOK', '4')), int(os.environ.get('STELYA', '120'))
    # КАТАЛОГ ГОТУЄТЬСЯ ОДИН РАЗ І ДО НИТОК. Перша чистка фіду переписує
    # `каталог_повний.xml` НА МІСЦІ; коли кілька проб стартують разом на брудному фіді,
    # одна пише, інші читають напівзаписаний (або `FileNotFoundError`) — червоні, що на
    # меншій кількості ниток зеленіють. Прилад не чекає, що хтось підготував теку.
    try:
        sys.path.insert(0, ДЖЕРЕЛА)
        import чистка_каталогу as _ЧК
        _ЧК.забезпечити_чистим('каталог_повний.xml')
    except BaseException as е:
        print('КАТАЛОГ НЕ ПІДГОТОВЛЕНО (%s): проби, що читають фід, можуть бути хибно червоні' % (str(е) or type(е).__name__)[:200])
    # Знімок — ПІСЛЯ підготовки каталогу: її запис — справа приладу, не проби.
    дерево = Дерево()
    print('проб знайдено %d · у черзі %d · ниток %d · стеля %d с · брудних шляхів до прогону %d'
          % (len(усі), len(черга), ниток, стеля, len(дерево.база)))
    звіт_файл = open(os.environ['ZVIT'], 'w', encoding='utf-8') if os.environ.get('ZVIT') else None
    звіти, у_льоті, підозрювані = {}, set(), set()
    # Підозрювані у зміні дерева — усі проби, що були в льоті між двома знімками:
    # нитки паралельні, і зміну, видиму після проби А, могла зробити ще жива Б.
    з_останнього = set()

    def гнати_з_обліком(ш):
        with дерево.замок:
            у_льоті.add(ш)
            з_останнього.add(ш)
        return гнати(ш, стеля)

    def записати(z):
        звіти[z['проба']] = z
        if звіт_файл:
            звіт_файл.write(json.dumps(dict(z, стан=стан(z)), ensure_ascii=False) + '\n')
            звіт_файл.flush()

    # `as_completed`, а не `map`: `map` віддає наслідки В ПОРЯДКУ ЧЕРГИ, тож одна повільна
    # проба тримала б звіт і `ZVIT` за собою (виміряно 27.09: 14 рядків журналу за 12 хв на
    # прогоні, де насправді вже було зміряно понад сотню). Прогін від цього не швидший —
    # чесним стає лише те, що видно на ходу.
    with cf.ThreadPoolExecutor(max_workers=ниток) as пул:
        завдання = {пул.submit(гнати_з_обліком, ш): ш for ш in черга}
        for готово, майбутнє in enumerate(cf.as_completed(завдання), 1):
            z = майбутнє.result()
            with дерево.замок:
                у_льоті.discard(z['проба'])
                зм = дерево.зміни()
                if зм:
                    дерево.повернути(зм)
                    if len(з_останнього) == 1:      # одна в льоті — приписано точно
                        z['дерево'] = зм
                    else:
                        підозрювані.update(з_останнього)
                        # одразу, а не лише після черги: прогін, що вмер на стелі сесії, не губить підозри
                        print('  ? ДЕРЕВО ЗМІНЕНО (повернуто): %s · у льоті: %s'
                              % (', '.join(зм), ', '.join(sorted(з_останнього))), flush=True)
                з_останнього.clear()
                з_останнього.update(у_льоті)
            записати(z)
            if стан(z) == 'червона':
                print('  ✗ %s rc %s (%.0f с)%s' % (z['проба'], z['rc'], z['сек'],
                                                   ' ДЕРЕВО: ' + ', '.join(z['дерево']) if z.get('дерево') else ''),
                      flush=True)
            elif готово % 50 == 0:
                print('  … %d / %d' % (готово, len(черга)), flush=True)
    if підозрювані:
        print('ДЕРЕВО ЗМІНЕНО, коли в льоті було кілька проб — підозрюваних %d жену поодинці: %s'
              % (len(підозрювані), ', '.join(sorted(підозрювані))), flush=True)
    for ш in sorted(підозрювані):
        z = гнати(ш, стеля)
        зм = дерево.зміни()
        if зм:
            дерево.повернути(зм)
            z['дерево'] = зм
        z['повтор'] = 'поодинці: дерево змінено при кількох у льоті'
        записати(z)
        print('  %s %s rc %s%s' % ('✗' if стан(z) == 'червона' else '·', ш, z['rc'],
                                  ' ДЕРЕВО: ' + ', '.join(зм) if зм else ''), flush=True)
    if звіт_файл:
        звіт_файл.close()
    брудне = дерево.зміни()
    дерево.прибрати()
    червоних = друкувати(list(звіти.values()), окремо, зайві, брудне)
    return 1 if (а.гейт and (червоних or брудне)) else 0


