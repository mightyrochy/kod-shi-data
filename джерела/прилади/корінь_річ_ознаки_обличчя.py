    import tempfile, textwrap
    with tempfile.TemporaryDirectory() as т:
        os.makedirs(os.path.join(т, "джерела", "показ"))
        тексти = {ім: textwrap.dedent(текст) for ім, текст in dict(_МАЛЕ_ЗЕРНО, **модулі).items()}
