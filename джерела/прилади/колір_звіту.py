"""Подання типізованого кольору у приладах: точка, межі або невідомо."""
from колір_річ import тип_кольору, точка_кольору, межі_кольору
import colorspace as CS


def колір_звіту(запис):
    """Дає hex лише виміру, межі інтервалу або None для невідомого кольору."""
    тип = тип_кольору(запис)
    if тип == "вимір":
        lab = точка_кольору(запис)
        return (запис.get("hex") or CS.hex_з_lab(lab)) if lab is not None else None
    межі = межі_кольору(запис)
    return dict(колір_тип=тип, межі=межі) if межі is not None else None


def підпис_кольору(запис):
    """Підписує вимір hex, інтервал усіма межами, невідоме явним словом."""
    колір = колір_звіту(запис)
    if not isinstance(колір, dict):
        return колір or "невідомо"
    L0, L1, C0, C1, дуга = колір["межі"]
    тон = "будь-який" if дуга is None else "%g…%g°" % tuple(дуга)
    return "інтервал L* %g…%g; C* %g…%g; h: %s" % (L0, L1, C0, C1, тон)
