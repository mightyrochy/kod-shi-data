# -*- coding: utf-8 -*-
"""Обсяг частини (ґ) розвідки «Приховані»: посилання правил роботи на слово власника і покриття їх вердиктами.

Наряд `аудит/наряди/Приховані-розвідка.md` (слово власника 31.10 14:26 і 14:51), частина (ґ): правило ядра, файлів
ролей і адаптерів, що каже більше чи інакше, ніж слово власника, на яке посилається. Прилад не судить — він лічить
знаменник (кожне посилання з детермінованим ід) і дає кандидатів у журналі `аудит/РІШЕННЯ_ВЛАСНИКА.md` за датою, щоб
вердикт на кожне стояв у `аудит/корені/Приховані-перелік-ґ.md`, а покриття рахував скрипт, а не сесія.

Одиниця — зворот правила з джерелом (ід `ґ:<файл>:<рядок>.<n>`), вид:
  власник     «власник» чи «власника» (адресат «власникові», «власником» — не джерело) й дата того самого звороту (до кінця дужок, «;», речення чи 160 знаків);
  власник-б/д «власник» як джерело в дужках чи після тире без дати — «(власник)», «— власник»;
  гола-дата   дата в дужках без слова-джерела («(29.10: …)», «(26.10)») — джерело не назване, тлумачиться як слово;
  інше        дата з іншим джерелом: вимір, урок, ревізія, розбір, PR — не слово власника, лічиться окремо.
Вердикт потрібен для видів «власник», «власник-б/д», «гола-дата»; «інше» — лише лічба.

Запуск з кореня репозиторію:
  python3 джерела/прилади/приховані_g_обсяг.py --одиниці          ід ⇥ вид ⇥ місце ⇥ дати ⇥ кандидати журналу ⇥ зворот
  python3 джерела/прилади/приховані_g_обсяг.py --перелік аудит/корені/Приховані-перелік-ґ.md
      покриття: одиниця покрита, коли її ід стоїть першою клітинкою рядка таблиці переліку (`| ґ:… | … |`).
"""
import argparse
import os
import re

КОРІНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ЖУРНАЛ = "аудит/РІШЕННЯ_ВЛАСНИКА.md"

# Правила роботи: ядро, адаптери, файли ролей і їхні додатки, на які ядро посилається як на правила (`аудит/КОД.md`,
# `аудит/МОДЕЛІ.md`, `аудит/проби/живі_порядок.md`), і план з картиною — ядро відсилає до них («Як працюємо», «Програма»)
# і вони посилаються на слово власника (рядок дошки 11963). `аудит/ПРОДУКТ.md` — частина (а), `аудит/СТАНДАРТ_КОДУ.md` — (б).
ПРАВИЛА_РОБОТИ = ("AGENTS.md", "CLAUDE.md", "GEMINI.md", "аудит/CHATGPT.md", "аудит/НОУТБУК.md",
                  "аудит/адаптери/CLAUDE_КЕРУВАННЯ.md", "аудит/адаптери/gemini/НАЛАШТУВАННЯ.md",
                  "аудит/адаптери/gemini/ЧЕРГА.md", "аудит/адаптери/gemini/СПОСТЕРІГАЧ.md",
                  "аудит/адаптери/gemini/m9v/ЩО_НАТИСНУТИ.md", "аудит/МЕНЕДЖЕР.md", "аудит/ДИСПЕТЧЕР.md",
                  "аудит/ВИКОНАВЕЦЬ.md", "аудит/ПЕРЕВІРКА.md", "аудит/КОД.md", "аудит/МОДЕЛІ.md",
                  "аудит/проби/живі_порядок.md", "аудит/ПЛАН.md", "аудит/КАРТИНА.md")

_ДАТА = re.compile(r"(?<![\d.])(\d{1,2})\.(09|10|11|12)(?![\d])")
_ВЛАСНИК = re.compile(r"власник\w*|власниц\w*", re.I)
_ІНШЕ = re.compile(r"вимір|урок|ревізі|розбір|замір|#\d|PR|проба|прогін|знахідк|перевірк|аудит|диспетчер|менеджер",
                   re.I)


def _дати(текст):
    return ["%02d.%s" % (int(д), м) for д, м in _ДАТА.findall(текст)]


def _межа(плаский, від, ліміт=160):
    """Кінець звороту: закрита дужка, «;», кінець речення, нова лапка чи ліміт знаків."""
    for м in re.finditer(r"\)|;|\.\s|\n\n", плаский[від:від + ліміт]):
        return від + м.start()
    return min(len(плаский), від + ліміт)


def одиниці():
    вихід = []
    журнал = _журнал()
    for ф in ПРАВИЛА_РОБОТИ:
        шлях = os.path.join(КОРІНЬ, ф)
        if not os.path.exists(шлях):
            continue
        текст = open(шлях, encoding="utf-8").read()
        плаский = текст.replace("\n", " ")
        на_рядку = {}
        зайняті = []

        def додати(поч, вид, дати, кін):
            н = текст.count("\n", 0, поч) + 1
            на_рядку[н] = на_рядку.get(н, 0) + 1
            канд = sorted({р for д in дати for р in журнал.get(д, [])})
            вихід.append(("ґ:%s:%d.%d" % (ф, н, на_рядку[н]), вид, "%s:%d" % (ф, н), ",".join(дати) or "—",
                          ",".join(map(str, канд[:12])) + ("…" if len(канд) > 12 else "") or "—",
                          плаский[max(0, поч - 110):кін + 1].strip()))
            зайняті.append((поч, кін))

        for з in _ВЛАСНИК.finditer(плаский):
            кін = _межа(плаский, з.end())
            дати = _дати(плаский[з.end():кін])
            if з.group(0).lower() not in ("власник", "власника"):
                continue  # «власникові (29.10: …)» — адресат перед уроком, не джерело (звірка пакета A)
            if дати and not any(б == кін for _, б in зайняті):  # кілька «власник…» одного звороту — одна одиниця
                додати(з.start(), "власник", дати, кін)
            elif з.group(0).lower() == "власник" and re.match(r"\)|\s*[),;]", плаский[з.end():з.end() + 2]) and (
                    "(" in плаский[max(0, з.start() - 3):з.start()] or "— " in плаский[max(0, з.start() - 3):з.start()]):
                додати(з.start(), "власник-б/д", [], з.end())
        for д in re.finditer(r"\(([^()]{0,40}?)(?<![\d.])(\d{1,2}\.(?:09|10|11|12))(?![\d.])", плаский):
            поч = д.start()
            if any(а <= поч <= б or а <= д.start(2) <= б for а, б in зайняті):
                continue
            перед = д.group(1)
            if re.search(r"(python|node|v|версі\w*)\s*$", перед, re.I):
                continue
            кін = _межа(плаский, д.start(2))
            if _ВЛАСНИК.search(перед):
                continue
            вид = "інше" if _ІНШЕ.search(перед) else "гола-дата"
            додати(поч, вид, _дати(плаский[д.start(2):кін]), кін)
    return sorted(вихід, key=lambda о: (ПРАВИЛА_РОБОТИ.index(о[2].rsplit(":", 1)[0]), int(о[2].rsplit(":", 1)[1])))


def _журнал():
    """Дата ДД.ММ → рядки журналу, де запис має цю дату: заголовок розділу (дата діє на його записи без своєї) чи
    жирний штамп запису «- **ДД.ММ…**»."""
    шлях = os.path.join(КОРІНЬ, ЖУРНАЛ)
    індекс = {}
    дати_розділу = []
    for н, рядок in enumerate(open(шлях, encoding="utf-8"), 1):
        if рядок.startswith("## "):
            дати_розділу = _дати(рядок)
            for д in дати_розділу:
                індекс.setdefault(д, []).append(н)
        elif рядок.startswith("- "):
            штамп = re.match(r"- \*\*([^*]+)\*\*", рядок)
            дати = _дати(штамп.group(1)) if штамп else _дати(рядок[:40])
            for д in дати or []:
                індекс.setdefault(д, []).append(н)
    return індекс


def main():
    п = argparse.ArgumentParser()
    п.add_argument("--одиниці", action="store_true")
    п.add_argument("--перелік")
    а = п.parse_args()
    усі = одиниці()
    if а.одиниці:
        for о in усі:
            print("\t".join(о))
        return
    види = {}
    for о in усі:
        види[о[1]] = види.get(о[1], 0) + 1
    print("одиниць %d: %s" % (len(усі), ", ".join("%s %d" % кв for кв in sorted(види.items()))))
    if а.перелік:
        покрито = set()
        for рядок in open(os.path.join(КОРІНЬ, а.перелік), encoding="utf-8"):
            м = re.match(r"\|\s*`?(ґ:[^|`]+?)`?\s*\|", рядок)
            if м:
                покрито.add(м.group(1))
        треба = [о[0] for о in усі if о[1] != "інше"]
        є = sum(1 for і in треба if і in покрито)
        print("потребують вердикту %d, з вердиктом %d (%.0f %%)" % (len(треба), є, 100.0 * є / max(1, len(треба))))
        зайві = sorted(покрито - {о[0] for о in усі})
        if зайві:
            print("ід переліку без одиниці (зсув рядків?): %d — %s" % (len(зайві), ", ".join(зайві[:8])))


if __name__ == "__main__":
    main()
