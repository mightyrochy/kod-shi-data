# -*- coding: utf-8 -*-
"""Показ у CI (не гейт): цитати нових записів журналу власника й розмір файлів правил.

python3 джерела/прилади/журнал_і_розмір_правил.py [--база РЕФ] [--md ФАЙЛ] [--корінь ШЛЯХ]
python3 джерела/прилади/журнал_і_розмір_правил.py --самоперевірка

1. Журнал `аудит/РІШЕННЯ_ВЛАСНИКА.md`: запис — пункт списку `- **…`. Новий — його тексту нема серед записів бази
   (`--база`, типово HEAD^1: у PR-злитті це база PR). У новому записі після першого «→» кожна пара
   «`файл` … — «цитата»» перевіряється: файл є, цитата стоїть у ньому на голові (пробіли й переноси зведені до
   одного пробілу). Нема файлу чи цитати — рядок у звіті. Записи без «→», без пар і старі — не чіпаються.
2. Розмір: межі читаються з рядка «Межі, тис. байтів» у `аудит/МЕНЕДЖЕР.md`, не дублюються тут (тут лише відповідність
   «назва в рядку → файли»). «Інші файли ролей і адаптери 6–10» міряються за верхньою межею. Понад межу — рядок з
   байтами (`wc -c`) і межею.

Код виходу 0 завжди, крім помилки приладу (нема журналу, нема рядка меж): показ, не гейт.
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

ЖУРНАЛ = "аудит/РІШЕННЯ_ВЛАСНИКА.md"
МЕНЕДЖЕР = "аудит/МЕНЕДЖЕР.md"
ПАРА = re.compile(r"`([^`\s]+\.\w+)`[^`—]*—\s*«([^»]+)»")
# Файли, на які вказують слова рядка меж без назви в зворотних лапках.
КАРТИНА = "аудит/КАРТИНА.md"
ІНШІ_РОЛІ_Й_АДАПТЕРИ = ("аудит/ВИКОНАВЕЦЬ.md", "аудит/ПЕРЕВІРКА.md", "аудит/НОУТБУК.md",
                        "аудит/CHATGPT.md", "GEMINI.md")


def норма(т):
    return " ".join(т.split())


def прочитати(корінь, шлях):
    with open(os.path.join(корінь, шлях), encoding="utf-8") as ф:
        return ф.read()


def записи(текст):
    """Пункти списку верхнього рівня: від «- **» до наступного такого."""
    зараз, всі = None, []
    for р in текст.split("\n"):
        if р.startswith("- **"):
            зараз = [р]
            всі.append(зараз)
        elif зараз is not None and (р.startswith("  ") or not р.strip()):
            зараз.append(р)
        else:
            зараз = None
    return ["\n".join(з).rstrip() for з in всі]


def пари(запис):
    if "→" not in запис:
        return []
    return ПАРА.findall(запис.split("→", 1)[1])


def звірити_журнал(корінь, старий_текст):
    стара = {норма(з) for з in записи(старий_текст)}
    нові = [з for з in записи(прочитати(корінь, ЖУРНАЛ)) if норма(з) not in стара]
    вади, пар_всього = [], 0
    for з in нові:
        для_запису = пари(з)
        пар_всього += len(для_запису)
        голова = норма(з)[:70]
        for файл, цитата in для_запису:
            шлях = os.path.join(корінь, файл)
            if not os.path.isfile(шлях):
                вади.append((голова, файл, цитата, "файлу нема"))
            elif норма(цитата) not in норма(прочитати(корінь, файл)):
                вади.append((голова, файл, цитата, "цитати нема у файлі"))
    return len(нові), пар_всього, вади


def межі(корінь):
    рядок = None
    for р in прочитати(корінь, МЕНЕДЖЕР).split("\n"):
        if р.lstrip("- ").startswith("Межі, тис. байтів"):
            рядок = р
            break
    if рядок is None:
        raise SystemExit("ПОМИЛКА ПРИЛАДУ: у %s нема рядка «Межі, тис. байтів»" % МЕНЕДЖЕР)
    # Рядок може переноситись: беремо до слів про журнал і довідку.
    текст = прочитати(корінь, МЕНЕДЖЕР)
    початок = текст.index("Межі, тис. байтів")
    кінець = текст.find("Журнал і довідка", початок)
    блок = норма(текст[початок:кінець if кінець > 0 else початок + 600])
    блок = блок.split("):", 1)[1] if "):" in блок else блок
    результат = {}
    for частина in блок.split(";"):
        м = re.search(r"(\d+)(?:[–-](\d+))?\s*\.?\s*$", частина.strip())
        if not м:
            continue
        межа = int(м.group(2) or м.group(1)) * 1000
        назва = частина[:м.start()]
        файли = re.findall(r"`([^`]+)`", назва)
        if "цей файл" in назва:
            файли.append(МЕНЕДЖЕР)
        if "картина" in назва:
            файли.append(КАРТИНА)
        if "інші файли ролей" in назва:
            файли += list(ІНШІ_РОЛІ_Й_АДАПТЕРИ)
        for ф in файли:
            результат[ф] = межа
    if not результат:
        raise SystemExit("ПОМИЛКА ПРИЛАДУ: у рядку меж не знайдено жодної пари файл—межа")
    return результат


def понад_межу(корінь):
    вихід, всього = [], 0
    for файл, межа in sorted(межі(корінь).items()):
        шлях = os.path.join(корінь, файл)
        if not os.path.isfile(шлях):
            continue
        всього += 1
        байт = os.path.getsize(шлях)
        if байт > межа:
            вихід.append((файл, байт, межа))
    return всього, вихід


def зібрати(корінь, база):
    р = subprocess.run(["git", "-C", корінь, "show", "%s:%s" % (база, ЖУРНАЛ)],
                       capture_output=True, text=True, encoding="utf-8")
    старий = р.stdout if р.returncode == 0 else ""
    нових, пар_всього, вади = звірити_журнал(корінь, старий)
    міряних, великі = понад_межу(корінь)
    вих = ["### Правила: журнал ↔ файли й розмір (показ, не гейт)", ""]
    вих.append("- Журнал: нових записів %d, пар «файл — цитата» %d, без збігу %d%s."
               % (нових, пар_всього, len(вади),
                  "" if р.returncode == 0 else " (база без журналу: усі записи нові)"))
    for голова, файл, цитата, чому in вади:
        вих.append("  - ⚠ %s: `%s` — «%s» (запис: %s…)" % (чому, файл, цитата[:100], голова))
    вих.append("- Розмір: міряно файлів %d, понад межу %d." % (міряних, len(великі)))
    for файл, байт, межа in великі:
        вих.append("  - ⚠ `%s`: %d байт, межа %d" % (файл, байт, межа))
    return "\n".join(вих) + "\n"


def самоперевірка():
    with tempfile.TemporaryDirectory() as т:
        for шлях, зміст in {
            "аудит/МЕНЕДЖЕР.md": "- Межі, тис. байтів (`wc -c`): `a.md` 1; цей файл 12;\n  інші файли ролей і адаптери 6–10.\n  Журнал і довідка — без межі.\n",
            "a.md": "перше  правило\nдруге правило " + "x" * 1100 + "\n",
            ЖУРНАЛ: "- **1.1** старий «ц» → `a.md` — «нема такого»\n"
                    "- **2.1** новий збіг: «ц» → `a.md` — «перше правило\n  друге» і `b.md` — «щось»\n"
                    "- **2.2** без стрілки `a.md` — «нема»\n"
                    "- **2.3** → `a.md`, «розділ» — «потреба в тестах»\n",
        }.items():
            os.makedirs(os.path.dirname(os.path.join(т, шлях)), exist_ok=True)
            open(os.path.join(т, шлях), "w", encoding="utf-8").write(зміст)
        старий = "- **1.1** старий «ц» → `a.md` — «нема такого»\n"
        нових, пар, вади = звірити_журнал(т, старий)
        assert (нових, пар) == (3, 3), (нових, пар)
        assert [(в[1], в[3]) for в in вади] == [("b.md", "файлу нема"), ("a.md", "цитати нема у файлі")], вади
        _, великі = понад_межу(т)
        assert [(f, b > m) for f, b, m in великі] == [("a.md", True)], великі
        assert межі(т)["аудит/МЕНЕДЖЕР.md"] == 12000 and межі(т)["GEMINI.md"] == 10000
    print("самоперевірка: ок")


def головна():
    п = argparse.ArgumentParser()
    п.add_argument("--база", default="HEAD^1")
    п.add_argument("--md")
    п.add_argument("--корінь", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
    п.add_argument("--самоперевірка", action="store_true")
    а = п.parse_args()
    if а.самоперевірка:
        return самоперевірка()
    звіт = зібрати(os.path.abspath(а.корінь), а.база)
    sys.stdout.write(звіт)
    if а.md:
        open(а.md, "w", encoding="utf-8").write(звіт)


if __name__ == "__main__":
    головна()
