"""Друкує шлях невизначеного тону через каталог, збагачення і суд палітри."""
import argparse
import json
import math
from pathlib import Path
import sys

ДЖЕРЕЛА = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ДЖЕРЕЛА))
sys.path.insert(0, str(ДЖЕРЕЛА / 'прилади'))


def градієнти():
    """Ті самі два градієнти, що в автоперевірці #1993."""
    import colorspace as К
    import річ_з_фото as Р
    for h in (0, 180):
        a, b = 12.5 * math.cos(math.radians(h)), 12.5 * math.sin(math.radians(h))
        rgb = []
        for _y in range(64):
            for x in range(64):
                d = (x % 32 - 15.5) * .5
                hx = К.hex_з_lab((65, a-d*math.sin(math.radians(h)), b+d*math.cos(math.radians(h))))
                rgb.append(tuple(int(hx[j:j+2], 16) for j in (1, 3, 5)))
        yield str(h), Р._вимір_плями(rgb, 64, 64, [True]*4096, 1, 'контрольований градієнт', None, True, поправка=False)


def факти():
    """Вимір → виробничі переходи → межі кольору та членство у палітрі."""
    import колір_річ as К
    import річ_з_фото as Р
    import фід_збагачення as З
    import жнива_колір as Ж
    import міст_вхід as М
    import palettes as П
    from поверхня_показ_212 import кадри
    вхід = json.loads((ДЖЕРЕЛА / 'стенд_вх.json').read_text(encoding='utf-8'))
    F, T = М.збірка(М.нормалізувати_вхід(dict(вхід)))[:2]
    палітра = П.палітра_практична(F)
    виміри = list(градієнти())
    for з, _кадр, _маска, _арр, пікселі, _rgb in кадри(ДЖЕРЕЛА.parent / 'аудит/проби/поверхня_212'):
        if з['ключ'] in ('11', '30', '39'):
            виміри.append((з['ключ'], Р.виміряти(пікселі, рамка=True)))
    вихід = []
    for ключ, вимір in виміри:
        річ = dict(ід=ключ, слот='верх', вимір=вимір)
        каталог = Р.запис_каталогу(річ)
        # Передаємо весь запис кольору: Lab сам по собі не містить невизначеності.
        палітра_ = Р.членство_в_палітрі(вимір if К.не_вимір(вимір) else вимір['lab'], палітра)
        сегмент = вимір['поверхня']['сегменти'][0]
        основний = Ж.звести_колір([сегмент], None, ['рожевий'])[0]
        к = {п: основний[п] for п in ('слово', 'hex', 'частка', 'колір_не_вимір') if п in основний}
        збагачений = {}
        З.накласти_колір(збагачений, dict(колір_основний=к, колір_другий=None, версія=2))
        суд = Р.вердикт(dict(річ, фото='ф1'), F, T)
        свідок = К.без_входу_кольору('K-COL-06', [(каталог,)], 'cannot_tell_item_is_neutral')
        вихід.append(dict(ключ=ключ, тон=сегмент['тон'], хрома=сегмент['хрома'],
                         lab=вимір['lab'], палітра=палітра_,
                         межі=К.межі_кольору(каталог), точка=К.точка_кольору(каталог),
                         збагачення_межі=К.межі_кольору(збагачений),
                         збагачення_точка=К.точка_кольору(збагачений),
                         суд_палітри=[з for з in суд['знахідки'] if з.get('правило') == 'K-PAL-17'],
                         суд_колір=суд['колір'], суд_свідок=[з['code'] for з in свідок['заяви']],
                         суд_заяви=[з['code'] for з in суд['повідомлення']['statements']]))
    return вихід


def main():
    """Записує факти без автоматичного оголошення живого приймання."""
    ап = argparse.ArgumentParser(description=__doc__)
    ап.add_argument('--вихід', type=Path, required=True)
    а = ап.parse_args()
    вихід = факти()
    а.вихід.write_text(json.dumps(вихід, ensure_ascii=False, indent=2), encoding='utf-8')
    for з in вихід:
        print(з['ключ'], 'тон', з['тон'], 'точка', з['точка'], 'палітра', з['палітра'])


if __name__ == '__main__':
    main()
