"""Заміри 4-го кола пілота 5190 без моделі: replay, лічба варіантів, мірило К4.

1) Записані відповіді 3-го кола (промпт c70011d9…) проходять новий валідатор:
   що відкинулось би й чому. 2) Лічба очікуваних варіантів за комами на рядках
   frozen40 і мірила К4 проти relation 3-го кола — вимір для ОЧІ, не код продукту.
3) Мірило К4: речі класу Г (рядок 6424) замінюються наступними контролями архіву
   за правилом нижче; список пишеться в аудит/пілот_5190/мірило_К4.json.
З аргументом <переклади.json> 4-го кола друкує ті самі лічби для його відповідей (без git і replay).
"""
import json
from pathlib import Path
import re
import subprocess
import sys

import рядки_кольору_5190 as П

АРХІВ = '3a6b9a43023a63d9b837473b2f235b09c3ee5717:аудит/перевірка/4920/незалежна_533e88ab/очні_оцінки.json'
# Клас Г за ОЧІ-5190 (№ 1, 2, 8, 19, 27, 31, 33, 39): кадр показу — колір, якого нема в словах речі.
КЛАС_Г = ('ж-00026@wearme.ua', 'ж-00036@wearme.ua', 'ж-01428@wearme.ua', 'ж-04116@wearme.ua',
          'ж-04251@wearme.ua', 'ж-04578@wearme.ua', 'ж-05067@wearme.ua', 'ж-07464@wearme.ua')
МІРИЛО = П.КОРІНЬ / 'аудит/пілот_5190/мірило_К4.json'


def відповіді_кола3():
    """Повертає записані відповіді 3-го кола з історії спроб, по row_id."""
    індекс = П.читати_json((П.ДАНІ / 'попередні_спроби.json').read_bytes())
    записи = {}
    for доказ in індекс['records']:
        if доказ.get('stage') == 'round3_c70011d9':
            запис = П.читати_json((П.ДАНІ / доказ['file']).read_bytes())
            рядки = П.читати_json(запис['request']['messages'][1]['content'])['rows']
            записи[рядки[0]['row_id']] = (запис, рядки)
    return записи


def фрагменти(сирий):
    """Рахує непорожні фрагменти між комами (крапкою з комою); slash і дужки — всередині фрагмента."""
    return [ф for ф in re.split(r'[,;]', сирий) if ф.strip()]


def мірило_к4(маніфест):
    """Замінює речі Г першими за порядком архіву контролями поза frozen40, де кадр — варіант зі слів.

    Правило вибору frozen40 — усі 40 кінцевих змін коду #959 — вичерпне: інших змін у тому
    diff нема. Тому наступні беруться з решти 41 контролю того самого архіву (зміни
    попередніх кіл мірила, порядок за id), де очна оцінка кадру показу «ТАК», а її назва
    кольору є в словах «Колір»/«~Колір» речі — тобто кадр показує варіант зі слів.
    """
    оцінки = json.loads(subprocess.check_output(['git', '-C', str(П.КОРІНЬ), 'show', АРХІВ]))
    заморожені = маніфест['source']['frozen40']
    слова = {}
    for в in маніфест['occurrences']:
        слова.setdefault(в['offer_id'], []).append(в['raw'].casefold())
    придатні = [о['id'] for о in оцінки if о['id'] not in заморожені and о['вердикт'] == 'ТАК'
                and any(о['після'].casefold() in с for с in слова.get(о['id'], []))]
    заміни = dict(zip(КЛАС_Г, придатні))
    if len(заміни) != len(КЛАС_Г) or not set(КЛАС_Г) <= set(заморожені):
        raise ValueError('Замало придатних контролів для заміни класу Г')
    речі = [заміни.get(ід, ід) for ід in заморожені]
    return {'version': '5190-measure-k4-v1', 'archive': АРХІВ, 'replaced': заміни, 'measure40': речі,
            'rule': ' '.join(мірило_к4.__doc__.split('\n\n')[1].split())}


def replay_кола3(коди):
    """Проганяє відповіді 3-го кола новим валідатором; друкує відкинуті."""
    записи = відповіді_кола3()
    відкинуті, відповіді = {}, {}
    for ід, (запис, рядки) in записи.items():
        перевірене = П.відповідь_пакета(запис['response'], рядки, коди)
        відповіді[ід] = П.читати_json(запис['response']['choices'][0]['message']['content'])['rows'][0]
        if ід in перевірене['rejected']:
            відкинуті[ід] = (рядки[0]['raw'], перевірене['rejected'][ід]['error'])
    print('replay 3-го кола новим валідатором:', len(записи), 'рядків, відкинулось би', len(відкинуті))
    for сирий, помилка in відкинуті.values():
        print('  ', json.dumps(сирий, ensure_ascii=False), '—', помилка)
    return відповіді


def головна():
    """Друкує числа replay (чи 4-го кола) і лічби варіантів; без аргументу пише мірило К4."""
    маніфест = П.підготувати()
    if len(sys.argv) > 1:
        відповіді = {р['row_id']: р['answer'] for р in П.читати_json(Path(sys.argv[1]).read_bytes())}
        мірило = П.читати_json(МІРИЛО.read_bytes())
    else:
        відповіді = replay_кола3(П.контракт()[3])
        мірило = мірило_к4(маніфест)
        П.зберегти(МІРИЛО, мірило)
    print('відповідей:', len(відповіді), '· known', sum(в['status'] == 'known' for в in відповіді.values()))
    назви = {}
    for відповідь in відповіді.values():
        for група in відповідь['variants']:
            for колір in група['colors']:
                назви.setdefault(колір['quote'].strip(' ,.').casefold(), set()).add(колір['code'])
    print('однакова назва → різні коди:', {н: sorted(к) for н, к in sorted(назви.items()) if len(к) > 1})
    print('заміни Г:', мірило['replaced'])
    for назва, речі in (('frozen40', маніфест['source']['frozen40']), ('мірило К4', мірило['measure40'])):
        рядки = {в['row_id']: в['raw'] for в in маніфест['occurrences'] if в['offer_id'] in речі}
        лічба = {}
        for ід, сирий in рядки.items():
            очікувано, відповідь = len(фрагменти(сирий)), відповіді.get(ід, {'relation': 'немає відповіді', 'variants': []})
            ключ = ('перелік' if очікувано > 1 else 'один фрагмент') + ' → ' + відповідь['relation'] + (
                ('' if len(відповідь['variants']) == очікувано else ' (варіантів ' + str(len(відповідь['variants'])) + ')')
                if відповідь['relation'] == 'alternatives' else '')
            лічба[ключ] = лічба.get(ключ, 0) + 1
        print(назва + ':', len(рядки), 'рядків, очікуваних варіантів за комами',
              sum(len(фрагменти(с)) for с in рядки.values()), '·', dict(sorted(лічба.items())))
    return 0


if __name__ == '__main__':
    sys.exit(головна())
