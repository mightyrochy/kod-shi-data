# -*- coding: utf-8 -*-
"""Перевіряє втрату читача, цикли архіву й складені шляхи без реального видалення."""
import unittest
import hashlib
import io
import json
import tempfile
from contextlib import redirect_stdout, redirect_stderr
from pathlib import Path
from unittest.mock import patch

from читачі_записів import вимір, посилання, звіт
from великі_записи import порушення


class Читачі(unittest.TestCase):
    """Сценарії, в яких помилка сканера загрожує видаленням потрібного запису."""

    def лічити(self, читання):
        """Подає маленьке повне дерево, а не файли поточної sparse-копії."""
        return вимір({п: (10, 'ша') for п in читання}, читання)

    def test_транзитивність_і_мертвий_цикл(self):
        """Живий звіт зберігає залежність, два мертві звіти — ні."""
        результат = self.лічити({
            'джерела/прилад.py': 'open("аудит/записи/живий.md")',
            'аудит/записи/живий.md': '`сусід.json`',
            'аудит/записи/сусід.json': '{}',
            'аудит/архів/а.md': '`б.md`',
            'аудит/архів/б.md': '`а.md`',
        })
        self.assertIn('аудит/записи/сусід.json', результат)
        self.assertNotIn('аудит/архів/а.md', результат)
        self.assertNotIn('аудит/архів/б.md', результат)

    def test_складений_шлях_і_шаблон(self):
        """Невідома змінна в Path і glob залишає записи з поясненням сумніву."""
        текст = 'p = Path("аудит") / "серія" / сцена / "знімки.json"'
        self.assertIn('аудит/серія/*/знімки.json', посилання('джерела/п.py', текст))
        результат = self.лічити({'джерела/п.py': текст,
                               'аудит/серія/день/знімки.json': '{}'})
        self.assertIn('сумнів', результат['аудит/серія/день/знімки.json'])

    def test_історія_не_читач(self):
        """Перенесене в історію посилання не утримує запис у main."""
        результат = self.лічити({'аудит/ПЛАН.md': '`abcdef123:аудит/архів/лог.txt`',
                               'аудит/архів/лог.txt': ''})
        self.assertNotIn('аудит/архів/лог.txt', результат)

    def test_невідома_сцена_не_видаляє(self):
        """Невідома сцена в прив'язаному до репозиторію шляху зберігає всі варіанти."""
        результат = self.лічити({'джерела/п.py': 'open(Path("аудит") / сцена / "дані.json")',
                               'аудит/а/дані.json': '{}', 'аудит/б/дані.json': '{}'})
        self.assertIn('аудит/а/дані.json', результат)
        self.assertIn('аудит/б/дані.json', результат)

    def test_glob_не_поширюється_на_весь_архів(self):
        """Маска звітів не означає читання сусідніх логів і підкаталогів."""
        результат = self.лічити({'аудит/ПЛАН.md': '`аудит/архів/*.md`',
                               'аудит/архів/звіт.md': '', 'аудит/архів/лог.txt': '',
                               'аудит/архів/глибше/інший.md': ''})
        self.assertIn('аудит/архів/звіт.md', результат)
        self.assertNotIn('аудит/архів/лог.txt', результат)
        self.assertNotIn('аудит/архів/глибше/інший.md', результат)

    def test_фільтр_CI_не_читач(self):
        """paths у workflow не зберігає архів, але команда CI зберігає вхід."""
        текст = 'on:\n  push:\n    paths:\n      - аудит/архів/**\njobs:\n  перевірка:\n    steps:\n      - run: python аудит/входи/проба.py\n'
        результат = self.лічити({'.github/workflows/ci.yml': текст,
                               'аудит/архів/сирий.txt': '', 'аудит/входи/проба.py': ''})
        self.assertNotIn('аудит/архів/сирий.txt', результат)
        self.assertIn('аудит/входи/проба.py', результат)

    def test_змінна_каталогу_з_glob(self):
        """Знаходить читача JSON через змінну Path і виклик rglob."""
        текст = 'from pathlib import Path\nтека = Path("аудит") / "серія"\nfor п in тека.rglob("*.json"): print(п.read_text())\n'
        self.assertIn('аудит/серія/**/*.json', посилання('джерела/п.py', текст))

    def test_межа_кінцевого_дерева(self):
        """Незмінена велика база й знятий сирий файл не блокують PR."""
        файли = {'аудит/база/повтор.json': (500, 'а'),
                 'аудит/новий/сирий.json': (101, 'б'),
                 'аудит/новий/доказ.txt': (100, 'в'), 'джерела/дані.json': (999, 'г')}
        змінені = {'аудит/новий/сирий.json', 'аудит/новий/доказ.txt',
                   'аудит/знятий/сирий.json', 'джерела/дані.json'}
        self.assertEqual(порушення(файли, змінені, 100), [('аудит/новий/сирий.json', 101)])

    def test_локальна_картка_і_пробіли(self):
        """Звіт читає свою картку, посилання з пробілами й percent-encoding не губиться."""
        результат = self.лічити({'аудит/ПЛАН.md': '[звіт](аудит/серія%20один/звіт.md)',
                               'аудит/серія один/звіт.md': '`знімки/картка.png`',
                               'аудит/серія один/знімки/картка.png': '',
                               'аудит/інша/знімки/картка.png': ''})
        self.assertIn('аудит/серія один/знімки/картка.png', результат)
        self.assertNotIn('аудит/інша/знімки/картка.png', результат)

    def test_документація_CLI_не_читач_архіву(self):
        """Приклад аргументу й коментар не читають логи; реальний open читає вхід."""
        текст = '\"\"\"Запуск: проба.py <вердикти.txt>\"\"\"\n# аудит/архів/лог.txt\nopen("аудит/вхід/дані.json")\n'
        результат = self.лічити({'джерела/п.py': текст,
                               'аудит/архів/вердикти.txt': '', 'аудит/архів/лог.txt': '',
                               'аудит/вхід/дані.json': '{}'})
        self.assertNotIn('аудит/архів/вердикти.txt', результат)
        self.assertNotIn('аудит/архів/лог.txt', результат)
        self.assertIn('аудит/вхід/дані.json', результат)
        результат = self.лічити({'аудит/проби/п.py': 'glob.glob("**/*")\nprint("%d/%d")',
                               'аудит/проби/архів/лог.txt': ''})
        self.assertNotIn('аудит/проби/архів/лог.txt', результат)

    def test_уточнення_не_звужує_змінений_код(self):
        """Після зміни читача старий доказ фільтра більше не дозволяє зняття."""
        текст = 'for ф in glob.glob("аудит/серія/*.*"): print(ф)'
        уточнення = {'джерела/п.py': {'sha256': hashlib.sha256(текст.encode()).hexdigest(),
                     'маски': [{'широка': 'аудит/серія/*.*', 'читані': ['аудит/серія/*.json']}]}}
        with patch('читачі_записів.перевірені_маски', return_value=уточнення):
            self.assertNotIn('аудит/серія/*.*', посилання('джерела/п.py', текст))
            self.assertIn('аудит/серія/*.*', посилання('джерела/п.py', текст + '\n# зміна'))

    def test_ревізія_фіксується_перед_виміром(self):
        """Пересування HEAD під час довгого виміру не змінює SHA його джерела."""
        with tempfile.TemporaryDirectory() as тека, patch('читачі_записів.git', return_value=b'abcdef123\n'), \
                patch('читачі_записів.дерево', return_value={}) as читання_дерева, \
                redirect_stdout(io.StringIO()), redirect_stderr(io.StringIO()):
            звіт('HEAD', Path(тека))
            читання_дерева.assert_called_once_with('abcdef123')
            результат = json.loads((Path(тека) / 'підсумок.json').read_text(encoding='utf8'))
            self.assertEqual(результат['ревізія'], 'abcdef123')

    def test_маска_класу_символів_і_робочий_каталог(self):
        """Читає glob [АБ] і зберігає невизначені входи після явного cd."""
        результат = self.лічити({'джерела/п.py': 'glob.glob("аудит/серія/[АБ]/*.json")',
                               'аудит/серія/А/вхід.json': '{}', 'аудит/серія/В/вхід.json': '{}',
                               '.github/workflows/ci.yml': 'steps:\n  - run: cd аудит/ще && cat *.json\n',
                               'аудит/ще/вхід.json': '{}'})
        self.assertIn('аудит/серія/А/вхід.json', результат)
        self.assertNotIn('аудит/серія/В/вхід.json', результат)
        self.assertIn('аудит/ще/вхід.json', результат)

    def test_відносні_шляхи_з_каталогів_запуску(self):
        """Літерал, складений Path і glob не гублять входи при запуску з джерела/."""
        for читач in ('джерела/проби/п.py', 'джерела/прилади/п.py'):
            for вираз in ('open("../аудит/серія/вхід.json")',
                          'open(Path("..") / "аудит" / "серія" / "вхід.json")',
                          'open(Path(__file__).resolve().parents[2] / "аудит" / "серія" / "вхід.json")',
                          'glob.glob("../аудит/серія/*.json")',
                          'Path("../аудит/серія").rglob("*.json")'):
                with self.subTest(читач=читач, вираз=вираз):
                    результат = self.лічити({читач: вираз,
                                           'аудит/серія/вхід.json': '{}',
                                           'аудит/інша/вхід.json': '{}'})
                    self.assertIn('аудит/серія/вхід.json', результат)
                    self.assertNotIn('аудит/інша/вхід.json', результат)

    def test_обидві_основи_та_транзитивність(self):
        """Неоднозначний відносний вхід зберігається від cwd і від файла, разом із залежністю."""
        результат = self.лічити({
            'джерела/проби/п.py': 'open("../аудит/серія/звіт.md")',
            'аудит/серія/звіт.md': '`поруч.json`',
            'аудит/серія/поруч.json': '{}',
            'джерела/аудит/серія/звіт.md': '',
        })
        self.assertIn('аудит/серія/звіт.md', результат)
        self.assertIn('аудит/серія/поруч.json', результат)

    def test_CI_від_кореня(self):
        """Відносні точний шлях і glob у команді CI рахуються від кореня дерева."""
        результат = self.лічити({
            '.github/workflows/ci.yml': 'steps:\n  - run: cat ./аудит/серія/*.json\n',
            'аудит/серія/вхід.json': '{}',
            'аудит/інша/вхід.json': '{}',
        })
        self.assertIn('аудит/серія/вхід.json', результат)
        self.assertNotIn('аудит/інша/вхід.json', результат)

    def test_явна_основа_та_відносний_cd(self):
        """__dirname має основу файла; відносний cd також враховує робочий каталог."""
        self.assertIn('аудит/серія/**', посилання(
            'джерела/прилади/п.js', 'path.join(__dirname, "../../аудит/серія")'))
        результат = self.лічити({
            'джерела/проби/п.sh': 'cd ../аудит/серія && cat *.json',
            'аудит/серія/вхід.json': '{}',
        })
        self.assertIn('аудит/серія/вхід.json', результат)

    def test_git_поточне_дерево_є_читачем(self):
        """ls-tree → show читає корпус HEAD навіть без прямого open на кожний файл."""
        текст = ('for г in ("HEAD", "origin/claude/архів"):\n'
                 '    for ф in git("ls-tree", "-r", "--name-only", г, "--", "../аудит/серія/"):\n'
                 '        git("show", "%s:%s" % (г, ф))\n')
        результат = self.лічити({'джерела/проби/п.py': текст,
                               'аудит/серія/вхід.txt': '', 'аудит/інша/вхід.txt': ''})
        self.assertIn('аудит/серія/вхід.txt', результат)
        self.assertNotIn('аудит/інша/вхід.txt', результат)

    def test_git_архів_і_метадані_не_читачі(self):
        """Історичний ref і перелік імен без читання blob не зобов'язують тримати корпус у main."""
        for текст in (
                'г, т = "origin/claude/архів", "../аудит/серія"\nф = git("ls-tree", "-r", г, т)\n'
                'git("show", "%s:%s" % (г, ф))\ngit("show", "HEAD:джерела/п.py")',
                'ф = git("ls-tree", "-r", "HEAD", "../аудит/серія")\ngit("show", "--stat", "HEAD")'):
            with self.subTest(текст=текст):
                self.assertNotIn('аудит/серія/вхід.txt', self.лічити({
                    'джерела/проби/п.py': текст, 'аудит/серія/вхід.txt': ''}))

    def test_git_словник_ревізій_і_каталогів(self):
        """Корпус із таблиці ref → каталог не губиться в параметрах функції читача."""
        текст = ('ГІЛКИ = {"HEAD": "аудит/серія"}\n'
                 'def файли(г, т):\n'
                 '    return subprocess.run(["git", "ls-tree", "-r", г, "../" + т])\n'
                 'for г, т in ГІЛКИ.items():\n'
                 '    for ф in файли(г, т):\n'
                 '        git("cat-file", "blob", ф)\n')
        self.assertIn('аудит/серія/вхід.txt', self.лічити({
            'джерела/проби/п.py': текст, 'аудит/серія/вхід.txt': ''}))


if __name__ == '__main__':
    unittest.main()
