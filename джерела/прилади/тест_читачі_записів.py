# -*- coding: utf-8 -*-
"""Перевіряє втрату читача, цикли архіву й складені шляхи без реального видалення."""
import unittest

from читачі_записів import вимір, посилання
from великі_записи import порушення


class Читачі(unittest.TestCase):
    """Сценарії, в яких помилка сканера загрожує видаленням потрібного запису."""

    def лічити(self, читання):
        """Подає маленьке повне дерево, а не файли поточної sparse-копії."""
        return вимір({п: (10, 'ша') for п in читання}, читання)

    def test_транзитивність_і_мертвий_цикл(self):
        """Живий звіт зберігає залежність, два мертві звіти — ні."""
        результат = self.лічити({
            'джерела/прилад.py': '"аудит/записи/живий.md"',
            'аудит/записи/живий.md': '`сусід.json`',
            'аудит/записи/сусід.json': '{}',
            'аудит/архів/а.md': '`б.md`',
            'аудит/архів/б.md': '`а.md`',
        })
        self.assertIn('аудит/записи/сусід.json', результат)
        self.assertNotIn('аудит/архів/а.md', результат)
        self.assertNotIn('аудит/архів/б.md', результат)

    def test_складений_шлях_і_шаблон(self):
        """Невідома змінна в Path і glob залишає записи з поясненням сумніву."""
        текст = 'p = Path("аудит") / "серія" / сцена / "знімки.json"'
        self.assertIn('аудит/серія/*/знімки.json', посилання('джерела/п.py', текст))
        результат = self.лічити({'джерела/п.py': текст,
                               'аудит/серія/день/знімки.json': '{}'})
        self.assertIn('сумнів', результат['аудит/серія/день/знімки.json'])

    def test_історія_не_читач(self):
        """Перенесене в історію посилання не утримує запис у main."""
        результат = self.лічити({'аудит/ПЛАН.md': '`abcdef123:аудит/архів/лог.txt`',
                               'аудит/архів/лог.txt': ''})
        self.assertNotIn('аудит/архів/лог.txt', результат)

    def test_неоднозначне_імя_не_видаляє(self):
        """Однакові basename лишаються до ручного розбору читача."""
        результат = self.лічити({'джерела/п.py': '"дані.json"',
                               'аудит/а/дані.json': '{}', 'аудит/б/дані.json': '{}'})
        self.assertIn('аудит/а/дані.json', результат)
        self.assertIn('аудит/б/дані.json', результат)

    def test_glob_не_поширюється_на_весь_архів(self):
        """Маска звітів не означає читання сусідніх логів і підкаталогів."""
        результат = self.лічити({'аудит/ПЛАН.md': '`аудит/архів/*.md`',
                               'аудит/архів/звіт.md': '', 'аудит/архів/лог.txt': '',
                               'аудит/архів/глибше/інший.md': ''})
        self.assertIn('аудит/архів/звіт.md', результат)
        self.assertNotIn('аудит/архів/лог.txt', результат)
        self.assertNotIn('аудит/архів/глибше/інший.md', результат)

    def test_фільтр_CI_не_читач(self):
        """paths у workflow не зберігає архів, але команда CI зберігає вхід."""
        текст = 'on:\n  push:\n    paths:\n      - аудит/архів/**\njobs:\n  перевірка:\n    steps:\n      - run: python аудит/входи/проба.py\n'
        результат = self.лічити({'.github/workflows/ci.yml': текст,
                               'аудит/архів/сирий.txt': '', 'аудит/входи/проба.py': ''})
        self.assertNotIn('аудит/архів/сирий.txt', результат)
        self.assertIn('аудит/входи/проба.py', результат)

    def test_змінна_каталогу_з_glob(self):
        """Знаходить читача JSON через змінну Path і виклик rglob."""
        текст = 'from pathlib import Path\nтека = Path("аудит") / "серія"\nfor п in тека.rglob("*.json"): print(п.read_text())\n'
        self.assertIn('аудит/серія/**/*.json', посилання('джерела/п.py', текст))

    def test_межа_кінцевого_дерева(self):
        """Незмінена велика база й знятий сирий файл не блокують PR."""
        файли = {'аудит/база/повтор.json': (500, 'а'),
                 'аудит/новий/сирий.json': (101, 'б'),
                 'аудит/новий/доказ.txt': (100, 'в'), 'джерела/дані.json': (999, 'г')}
        змінені = {'аудит/новий/сирий.json', 'аудит/новий/доказ.txt',
                   'аудит/знятий/сирий.json', 'джерела/дані.json'}
        self.assertEqual(порушення(файли, змінені, 100), [('аудит/новий/сирий.json', 101)])


if __name__ == '__main__':
    unittest.main()
