# -*- coding: utf-8 -*-
"""Тижневий зріз поточної дошки або історичної розмітки, без сторонніх пакетів.

python джерела/прилади/дошка_зріз.py --від 2026-10-19 --до 2026-10-26
python джерела/прилади/дошка_зріз.py --від 2026-10-19 --до 2026-10-26 --розмітка аудит/дошка_розбір_глибинний/розмітка.tsv

Дошка: нові рядки — за датою появи, закриття — за датою останнього закриття
у поточному стані. Старі рядки без полів не вгадуються: показано покриття.
Розмітка: дати закриття невідомі, тому закриття — стан КОГОРТИ нових рядків,
не потік закриттів тижня. Вибір дат має включати тиждень розмітки цілком.
Вільні механізми старої розмітки потрапляють в «інше», без вигаданої ГП.
За кількох ГП рядок входить у кожну один раз; загалом — лише один раз.
"""
import argparse
import csv
import sys
from datetime import date
from pathlib import Path

from дошка_поля import МЕХАНІЗМИ, БЛОК, ВИЯВЛЕНО, групи, метадані, перевірити_поля
from згорнути_дошку import ДОШКА, РЯДОК, межі_стану, ранг_рядка

ТИЖНІ_РОЗМІТКИ = {
    '1) 14–20.09': ('2026-09-14', '2026-09-20'),
    '2) 21–27.09': ('2026-09-21', '2026-09-27'),
    '3) 28.09–04.10': ('2026-09-28', '2026-10-04'),
    '4) 05–11.10': ('2026-10-05', '2026-10-11'),
    '5) 12–18.10': ('2026-10-12', '2026-10-18'),
    '6) 19.10–': ('2026-10-19', '2026-10-26'),
}
ДЖЕРЕЛА_РОЗМІТКИ = {
    'власник': 'власник', 'живий-прогін': 'живий', 'стенд-проба-CI': 'проба',
    'виконавець-побіжно': 'виконавець', 'перевірка-рецензія': 'перевірка',
    'менеджер-куратор': 'менеджер', 'тестувальниця': 'тестувальниця',
}


def у_межах(дата, від, до):
    return bool(дата) and від <= дата <= до


def читати_дошку(шлях):
    записи, без_полів = [], 0
    for рядок in Path(шлях).read_text(encoding='utf-8').splitlines():
        номер = РЯДОК.match(рядок)
        if not номер:
            continue
        if not БЛОК.search(рядок):
            без_полів += 1
            continue
        межі = межі_стану(рядок)
        if not межі:
            raise ValueError(f'рядок {номер[1]}: відсутня клітинка статусу')
        від, до = межі
        # Блок закриття в статусі — новіший за попередній доказ у решті рядка.
        стан = рядок[від:до]
        решта = рядок[:від] + рядок[до:]
        поява = метадані(решта)
        поля = {**поява, **метадані(стан)}
        закрито = ранг_рядка(рядок) > 1
        вади = перевірити_поля(решта, новий='дата' in поля)
        вади += перевірити_поля(стан, закрито=закрито, дата_появи=поява.get('дата', ''))
        if вади:
            raise ValueError(f'рядок {номер[1]}: {"; ".join(вади)}')
        джерело = ВИЯВЛЕНО.search(рядок)
        записи.append({**поля, 'номер': номер[1], 'джерело': джерело[1].strip() if джерело else '',
                       'закрито': закрито})
    return записи, без_полів


def читати_розмітку(шлях, від, до):
    записи, без_дати = [], 0
    with open(шлях, encoding='utf-8', newline='') as файл:
        for рядок in csv.DictReader(файл, delimiter='\t'):
            тиждень = ТИЖНІ_РОЗМІТКИ.get(рядок['тиждень'])
            if not тиждень:
                без_дати += 1
                continue
            початок, кінець = тиждень
            if кінець < від or початок > до:
                continue
            if not (від <= початок and кінець <= до):
                raise ValueError(f'розмітка не має денних дат: включіть увесь тиждень {рядок["тиждень"]}')
            перелік = [м if м in МЕХАНІЗМИ else 'інше' for м in рядок['механізм'].split('+')]
            рід = рядок['рід'].removeprefix('вада-')
            рід = {'даних': 'дані', 'мірила': 'мірило', 'процесу': 'процес'}.get(рід, рід)
            записи.append({'номер': рядок['n'], 'дата': початок, 'рід': рід,
                           'попередник': рядок['повтор'], 'механізм': '+'.join(перелік),
                           'джерело': ДЖЕРЕЛА_РОЗМІТКИ.get(рядок['виявлено'], ''),
                           'закрито': рядок['доказ'] != '—',
                           'доказ': 'документ' if рядок['доказ'] == 'текст' else рядок['доказ']})
    return записи, без_дати


def підрахувати(записи, від, до, когорта=False):
    нові = [р for р in записи if у_межах(р.get('дата'), від, до)]
    закриті = [р for р in записи if р['закрито'] and
               (р in нові if когорта else у_межах(р.get('дата-закриття'), від, до))]
    видимі = [р for р in нові if р.get('рід') == 'видима']
    лічба = {'нових': len(нові), 'повтор': sum(р['попередник'] != 'ні' for р in нові),
             'регресія': sum(р['попередник'].startswith('регресія') for р in нові),
             'закриттів': len(закриті), 'без доказу': sum(р['доказ'] == 'нема' for р in закриті),
             'видимих': len(видимі), 'видимих авто': sum(р['джерело'] == 'проба' for р in видимі)}
    for джерело in ('власник', 'живий', 'проба', 'виконавець', 'перевірка'):
        лічба[джерело] = sum(р['джерело'] == джерело for р in нові)
    for рід in ('мірило', 'процес'):
        лічба[рід] = sum(р.get('рід') == рід for р in нові)
    return лічба


def частка(число, усіх):
    return f'{число}/{усіх} ({100 * число / усіх:.0f} %)' if усіх else '0/0 (н/д)'


def звіт(записи, від, до, когорта=False):
    колонки = ('повтор', 'регресія', 'без доказу', 'видимих авто',
               'власник', 'живий', 'проба', 'виконавець', 'перевірка', 'мірило', 'процес')
    рядки = ['| група | нових | закриттів | видимих | ' + ' | '.join(колонки) + ' |',
             '|---|' + '---|' * (len(колонки) + 3)]
    for група in ('Усього', *sorted(set(МЕХАНІЗМИ.values()))):
        вибрані = записи if група == 'Усього' else [р for р in записи if група in групи(р['механізм'])]
        лічба = підрахувати(вибрані, від, до, когорта)
        значення = []
        for колонка in колонки:
            база = 'закриттів' if колонка == 'без доказу' else 'видимих' if колонка == 'видимих авто' else 'нових'
            значення.append(частка(лічба[колонка], лічба[база]))
        рядки.append(f'| {група} | {лічба["нових"]} | {лічба["закриттів"]} | {лічба["видимих"]} | ' +
                     ' | '.join(значення) + ' |')
    return '\n'.join(рядки)


def головна():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('--від', required=True, type=date.fromisoformat)
    парсер.add_argument('--до', required=True, type=date.fromisoformat)
    парсер.add_argument('--дошка', default=ДОШКА)
    парсер.add_argument('--розмітка')
    арг = парсер.parse_args()
    if арг.від > арг.до:
        парсер.error('--від має бути не пізніше --до')
    від, до = арг.від.isoformat(), арг.до.isoformat()
    try:
        записи, невідомі = (читати_розмітку(арг.розмітка, від, до) if арг.розмітка else читати_дошку(арг.дошка))
        print(f'Зріз {від} — {до}. Джерело: {арг.розмітка or арг.дошка}')
        print(f'Покриття: рядків із полями {len(записи)}; старих без полів/дати {невідомі}.')
        print('Закриття: стан когорти нових рядків.' if арг.розмітка else
              'Закриття: останнє закриття поточного стану за датою-закриття; нові — за датою появи.')
        print('ГП можуть перетинатися; «не визначено» не приписується глибинній причині.')
        print(звіт(записи, від, до, когорта=bool(арг.розмітка)))
    except (OSError, ValueError, KeyError, TypeError) as помилка:
        print(f'ПОМИЛКА: {помилка}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(головна())
