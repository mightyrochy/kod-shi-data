def _md5(дані):
    """md5 байтів, hex."""
    return _hl.md5(дані).hexdigest()


def _md5_файла(шлях):
    """md5 файла частинами — фід важить 50 МБ."""
    х = _hl.md5()
    with open(шлях, "rb") as f:
        for шматок in iter(lambda: f.read(1 << 20), b""):
            х.update(шматок)
    return х.hexdigest()


def модулі_побудови(тека):
    """Статичне замикання імпортів від `фід_каталог` у межах теки — код, що будує базу.

    Той самий AST-підхід, що `склад.модулі_системи` (регулярка брала лише перше ім'я
    рядка), але від іншого кореня й без звірки складу продукту. Імпорти всередині функцій
    теж ідуть у замикання: побудова кличе частину модулів ліниво."""
    import ast as _ast
    мод = {f[:-3] for f in _os.listdir(тека) if f.endswith(".py")}
    треба, край = set(), {"фід_каталог"}
    while край:
        м = край.pop()
        треба.add(м)
        дерево = _ast.parse(open(_os.path.join(тека, м + ".py"), encoding="utf-8").read())
        for в in _ast.walk(дерево):
            if isinstance(в, _ast.Import):
                край |= {а.name.split(".")[0] for а in в.names} & мод - треба
            elif isinstance(в, _ast.ImportFrom) and в.level == 0 and в.module:
                край |= {в.module.split(".")[0]} & мод - треба
    return sorted(треба)


# ── КОРТЕЖІ: ДЕ JSON ДАВ БИ СПИСОК ──────────────────────────────────────────
def _шляхи_кортежів(v, шлях=()):
    """Шляхи всередині значення, де стоїть кортеж; індекси списків — "*"."""
    if isinstance(v, tuple):
        yield шлях
        for x in v:
            yield from _шляхи_кортежів(x, шлях + ("*",))
    elif isinstance(v, list):
        for x in v:
            yield from _шляхи_кортежів(x, шлях + ("*",))
    elif isinstance(v, dict):
        for к, x in v.items():
            yield from _шляхи_кортежів(x, шлях + (к,))


def _у_кортежі(v, шляхи, шлях=()):
    """Списки на `шляхах` — назад у кортежі (зворотне до JSON)."""
    if isinstance(v, list):
        v = [_у_кортежі(x, шляхи, шлях + ("*",)) for x in v]
        return tuple(v) if шлях in шляхи else v
    if isinstance(v, dict):
        return {к: _у_кортежі(x, шляхи, шлях + (к,)) for к, x in v.items()}
    return v


def _копія(v):
    """Значення з оферу — у запис власною копією: запис далі по течії дописують, а офер
    той самий бачить картка показу. Незмінне (рядок, число, None) не копіюється."""
    if isinstance(v, list):
        return [_копія(x) for x in v]
    if isinstance(v, dict):
        return {к: _копія(x) for к, x in v.items()}
    return v


def однакові(a, b):
    """Рівність із типами й порядком ключів: кортеж ≠ список, 1 ≠ 1.0 ≠ True."""
    if type(a) is not type(b):
        return False
    if isinstance(a, dict):
        return list(a) == list(b) and all(однакові(a[к], b[к]) for к in a)
    if isinstance(a, (list, tuple)):
        return len(a) == len(b) and all(однакові(x, y) for x, y in zip(a, b))
    return a == b


# ── ПОБУДОВА (ЗБИРАЧ) ─────────────────────────────────────────────────────────
def зібрати(шлях_фіду, тека=None, байти_модулів=None):
    """Будує таблицю з фіду тим самим кодом, що й продукт на льоту, і звіряє її.

    `байти_модулів` — {ім'я: байти}, як модулі їдуть у вантаж (збирач стрипає їх); без
    нього — файли теки як є (прогін у джерелах). Повертає словник таблиці; падає, коли
    відновлена з таблиці база хоч на знак розходиться з побудованою."""
    import builtins as _bi
    import trace as _СЛ
    import feed as _Ф, фід_каталог as _ФК, фід_розбір as _ФР, фід_слот as _ФС
    тека = тека or _os.path.dirname(_os.path.abspath(_ФК.__file__))
    import tempfile as _tf
    кеш_кол = _os.path.join(_tf.mkdtemp(), "кеш_кольорів.json")   # порожній, як у продукті
    with open(кеш_кол, "w", encoding="utf-8") as f:
        f.write("{}")
    відкрито, _open, _stat = [], _bi.open, _os.stat

    def _слідкувати(ф, *а, **к):
        відкрито.append(ф)
        return _open(ф, *а, **к)

    # ПИТАНІ Й ВІДСУТНІ ФАЙЛИ — ТЕЖ ВХІД: `фід_кадр_колір.читати_кадри` питає
    # `каталог_кадри.json(.gz)` через `os.path.exists`, і без файла база інша, ніж із ним.
    # Файл, якого при побудові не було, лягає в ключ як відсутній — коли він з'явиться,
    # таблиця застаріє, а не вживеться мовчки (`os.path.exists`/`getmtime` кличуть `os.stat`)
    def _слідкувати_stat(ф, *а, **к):
        відкрито.append(ф)
        return _stat(ф, *а, **к)
    # кеші читачів файлів порожні — інакше файл, прочитаний раніше в цьому процесі, не
    # відкрився б під гачком і випав би з ключа (так випало збагачення на першій пробі)
    import фід_збагачення as _ФЗ, фід_фото as _ФФ, фід_кадр_колір as _ФКК, назва_речі as _НР
    for к_ in (_ФЗ._ЗБАГАЧЕННЯ_КЕШ, _ФФ._ПОКАЗ_КЕШ, _ФКК._КАДРИ_КЕШ, _НР._КАРТКИ_КЕШ, _ФС._ТИП_КЕШ):
        к_.clear()
    було_увімк, було = _СЛ._УВІМК, _СЛ._ЗАПИСИ
    _СЛ.почати()
    _bi.open, _os.stat = _слідкувати, _слідкувати_stat
    try:
        зб = _Ф.читати_збагачення()
        б = _ФК._прочитати_каталог(шлях_фіду, 0, кеш_кол, зб)
    finally:
        _bi.open, _os.stat = _open, _stat
        слід = [dict(з) for з in _СЛ._ЗАПИСИ]
        _СЛ._УВІМК, _СЛ._ЗАПИСИ = було_увімк, було
        _os.remove(кеш_кол)
        _os.rmdir(_os.path.dirname(кеш_кол))
    тип_кеш_б = list(_ФС._ТИП_КЕШ.items())
    офери = _ФР.офери_фіду(шлях_фіду)
    поз = {o["id"]: і for і, o in enumerate(офери)}
    записи = б["каталог"]
    без_оферу = [r["id"] for r in записи if r["id"] not in поз]
    if без_оферу:
        raise SystemExit("таблиця каталогу: записи без оферу у фіді — %s" % без_оферу[:5])
    # ── РІЗНИЦЯ ДО ОФЕРУ, СТОВПЧИКАМИ ────────────────────────────────────────
    н = len(записи)
    імена, н_імені = [], {}
    кортежі, порядки, номер, порядок, стовпці = {}, [], {}, [], {}
    for і, r in enumerate(записи):
        o = офери[поз[r["id"]]]
        for к in r:
            if к not in н_імені:
                н_імені[к] = len(імена)
                імена.append(к)
        к_ = tuple(н_імені[к] for к in r)
        if к_ not in номер:
            номер[к_] = len(порядки)
            порядки.append(list(к_))
        порядок.append(номер[к_])
        for к, v in r.items():
            for ш in _шляхи_кортежів(v):
                кортежі.setdefault(к, set()).add(ш)
            if к in o and однакові(o[к], v):
                continue
            if _позначка(v):
                raise SystemExit("таблиця каталогу: значення поля %s має форму позначки таблиці" % к)
            фото = o.get("фото") or []
            стовпці.setdefault(к, {})[і] = ([ПОСИЛАННЯ, "фото", фото.index(v)]
                                           if isinstance(v, str) and v in фото else v)
    поля = {}
    for к, зн in sorted(стовпці.items()):
        if 2 * len(зн) >= н:
            поля[к] = {"щ": [зн.get(і, ПРОПУСК) for і in range(н)]}
        else:
            іі = sorted(зн)
            поля[к] = {"і": іі, "з": [зн[і] for і in іі]}
    # ── КЕШ ТИПІВ: КЛЮЧ — НОМЕРОМ ОФЕРУ, ДЕ ВІН ТАКИЙ САМИЙ ─────────────────────
    перший = {}
    for і, o in enumerate(офери):
        перший.setdefault((str(o.get("категорія", "")), _ФС.назва_суду(o)), і)
    тк = [([перший[(кат, назва)], слот, тип] if (кат, назва) in перший else [кат, назва, слот, тип])
          for (кат, назва, слот), тип in тип_кеш_б]
    корінь = _os.path.abspath(тека)
    питані = {_os.path.abspath(_os.fspath(ф)) for ф in відкрито if isinstance(ф, (str, _os.PathLike))}
    дані = [ф for ф in питані
            if _os.path.dirname(ф) == корінь and not ф.endswith(".py") and not _os.path.isdir(ф)
            and ф not in (_os.path.abspath(шлях_фіду), _os.path.abspath(кеш_кол))]
    т = dict(версія=ВЕРСІЯ, фід_ім=_os.path.basename(шлях_фіду),
             ключ=ключ(шлях_фіду, тека, байти_модулів, дані),
             записи=[поз[r["id"]] for r in записи], імена=імена, поля=поля,
             порядки=порядки, порядок=порядок,
             кортежі={к: sorted(list(ш) for ш in шш) for к, шш in sorted(кортежі.items())},
             лічильники={к: v for к, v in б.items() if к != "каталог"},
             кортежі_лічильників={к: sorted(list(ш) for ш in set(_шляхи_кортежів(v)))
                                  for к, v in б.items() if к != "каталог"},
             порядок_бази=list(б), слід=слід, тип_кеш=тк)
    # ── ЗВІРКА: ТЕ, ЩО ВІДНОВИТЬ ПРОДУКТ, — ТА САМА БАЗА ДО ЗНАКА ─────────────
    т_json = _json.loads(_json.dumps(т, ensure_ascii=False))
    відн = відновити(т_json, офери)
    if тип_кеш(т_json, офери) != тип_кеш_б:
        raise SystemExit("таблиця каталогу: відновлений кеш типів розходиться з побудованим")
    if not однакові(відн, б):
        різні = [r["id"] for r, в in zip(б["каталог"], відн.get("каталог") or []) if not однакові(r, в)]
        raise SystemExit("таблиця каталогу: відновлена база розходиться з побудованою — записів %d "
                         "(перші: %s); лічильники однакові: %s"
                         % (len(різні), різні[:5], all(однакові(б[к], відн.get(к)) for к in б if к != "каталог")))
    return т


def ключ(шлях_фіду, тека, байти_модулів=None, файли_даних=()):
    """Ключ таблиці: md5 фіду, коду побудови, даних і умови виклику (див. докстрінг модуля)."""
    мод = {}
    for м in модулі_побудови(тека):
        дані = (байти_модулів or {}).get(м)
        if дані is None:
            with open(_os.path.join(тека, м + ".py"), "rb") as f:
                дані = f.read()
        мод[м] = _md5(дані)
    # файл, якого нема, — None: побудова його питала й не знайшла (див. `зібрати`)
    return dict(фід=_md5_файла(шлях_фіду), код=мод,
                дані={_os.path.basename(ф): (_md5_файла(ф) if _os.path.isfile(ф) else None)
                      for ф in sorted(set(файли_даних))},
                умови=dict(ліміт_фото=0, кеш_кольорів="{}"))


def записати(т, шлях):
    """Таблиця у файл — детерміновано (ключі по черзі, gzip без часу), як решта вантажу."""
    сирі = _json.dumps(т, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    with open(шлях, "wb") as f:
        with _gz.GzipFile(fileobj=f, mode="wb", compresslevel=9, mtime=0) as г:
            г.write(сирі)


# ── ВІДНОВЛЕННЯ (ПРОДУКТ) ─────────────────────────────────────────────────────
def _позначка(v):
    """Чи має значення форму службової позначки таблиці (тоді кодувати його не можна)."""
    return ((isinstance(v, str) and v == ПРОПУСК)
            or (isinstance(v, list) and len(v) == 3 and v[0] == ПОСИЛАННЯ))


def відновити(т, офери):
    """База з таблиці й оферів фіду: {каталог, офферів, у_слотах, без_слота, збої,
    розкиди, відкинуто} — той самий словник, що `_прочитати_каталог`."""
    н = len(т["записи"])
    імена = т["імена"]
    стовпці = {}
    for к, ст in т["поля"].items():
        if "щ" in ст:
            стовпці[к] = ст["щ"]
        else:
            с = [ПРОПУСК] * н
            for і, з in zip(ст["і"], ст["з"]):
                с[і] = з
            стовпці[к] = с
    кортежі = {к: {tuple(ш) for ш in шш} for к, шш in т["кортежі"].items()}
    порядки = [[імена[к] for к in п] for п in т["порядки"]]
    порожньо = [ПРОПУСК] * н
    записи = []
    for і, п in enumerate(т["записи"]):
        o = офери[п]
        r = {}
        for к in порядки[т["порядок"][і]]:
            v = стовпці.get(к, порожньо)[і]
            if isinstance(v, str):
                if v == ПРОПУСК:
                    v = _копія(o[к])
            elif isinstance(v, list) and len(v) == 3 and v[0] == ПОСИЛАННЯ:
                v = o[v[1]][v[2]]
            r[к] = _у_кортежі(v, кортежі[к]) if к in кортежі else v
        записи.append(r)
    б = {"каталог": записи}
    for к, v in т["лічильники"].items():
        б[к] = _у_кортежі(v, {tuple(ш) for ш in т["кортежі_лічильників"].get(к) or []})
    # порядок ключів бази — як у `_прочитати_каталог`
    return {к: б[к] for к in т["порядок_бази"]}


def тип_кеш(т, офери):
    """Записи `фід_слот._ТИП_КЕШ`, які лишила побудова: [((категорія, назва, слот), тип)]."""
    from фід_слот import назва_суду
    вих = []
    for з in т["тип_кеш"]:
        if len(з) == 3:
            o = офери[з[0]]
            вих.append(((str(o.get("категорія", "")), назва_суду(o), з[1]), з[2]))
        else:
            вих.append(((з[0], з[1], з[2]), з[3]))
    return вих


def _таблиця_поруч(тека):
    """Шлях до таблиці у вантажі (поруч із `feed.py`) або None."""
    ш = _os.path.join(тека, ІМ)
    return ш if _os.path.exists(ш) else None


_MD5_ФІДУ = {}


def база(шлях_фіду, ліміт_фото, кеш):
    """(база, слід, тип_кеш) з таблиці вантажу — або None, коли таблиці нема чи вона не
    для цих входів. Що саме вирішило, лягає в `СТАН` (див. докстрінг модуля)."""
    import feed as _Ф, фід_розбір as _ФР
    тека = _os.path.dirname(_os.path.abspath(_Ф.__file__))
    шлях_т = _таблиця_поруч(тека)
    if not шлях_т:
        СТАН.clear(); СТАН.update(стан="нема", чому="у вантажі нема " + ІМ)
        return None
    # ТАБЛИЦЯ НЕ ТРИМАЄТЬСЯ В ПАМ'ЯТІ: після відновлення базу тримає `фід_каталог._КЕШ_БАЗИ`,
    # а розібраний JSON — десятки МБ, яких на телефоні шкода; знадобиться ще — прочитається
    try:
        with _gz.open(шлях_т, "rt", encoding="utf-8") as f:
            т = _json.load(f)
    except Exception as e:
        СТАН.clear(); СТАН.update(стан="зіпсована", чому="%s: %s" % (type(e).__name__, str(e)[:200]))
        return None
    чому = _розбіжність(т, шлях_фіду, тека, ліміт_фото, кеш)
    if чому:
        СТАН.clear(); СТАН.update(стан="застаріла", чому=чому)
        return None
    офери = _ФР.офери_фіду(шлях_фіду)
    б = відновити(т, офери)
    СТАН.clear(); СТАН.update(стан="вжито", записів=len(б["каталог"]), фід=т["ключ"]["фід"][:12])
    return б, [dict(з) for з in т.get("слід") or []], тип_кеш(т, офери)


def _розбіжність(т, шлях_фіду, тека, ліміт_фото, кеш):
    """Що в ключі таблиці не збігається з тим, що лежить поруч, — рядком; або None."""
    if т.get("версія") != ВЕРСІЯ:
        return "версія таблиці %s, код читає %s" % (т.get("версія"), ВЕРСІЯ)
    к = т.get("ключ") or {}
    if (ліміт_фото or 0) != 0:
        return "ліміт_фото %s: таблиця збудована без виміру фото" % ліміт_фото
    try:
        with open(кеш, encoding="utf-8") as f:
            if _json.load(f) != {}:
                return "кеш кольорів не порожній: таблиця збудована з порожнім"
    except (OSError, ValueError):
        pass
    try:
        ст = _os.stat(шлях_фіду)
        кл = (_os.path.abspath(шлях_фіду), ст.st_mtime_ns, ст.st_size)
        if кл not in _MD5_ФІДУ:
            _MD5_ФІДУ.clear()
            _MD5_ФІДУ[кл] = _md5_файла(шлях_фіду)
        if _MD5_ФІДУ[кл] != к.get("фід"):
            return "фід інший (md5 %s, таблиця — %s)" % (_MD5_ФІДУ[кл][:12], str(к.get("фід"))[:12])
    except OSError as e:
        return "фід не читається: %s" % e
    змінено = []
    for м, md5 in sorted((к.get("код") or {}).items()):
        ш = _os.path.join(тека, м + ".py")
        if not _os.path.exists(ш) or _md5_файла(ш) != md5:
            змінено.append(м)
    if змінено:
        return "змінився код побудови: " + ", ".join(змінено)
    for ім, md5 in sorted((к.get("дані") or {}).items()):
        ш = _os.path.join(тека, ім)
        є = _os.path.isfile(ш)
        if md5 is None:
            if є:
                змінено.append(ім + " (з'явився, при побудові його не було)")
        elif not є or _md5_файла(ш) != md5:
            змінено.append(ім)
    if змінено:
        return "змінились дані побудови: " + ", ".join(змінено)
    return None


