"""ТАБЛИЦЯ КАТАЛОГУ — база фіду, збудована один раз під час збірки, а не на телефоні.

Рішення власника 27.09.2026: «Навіщо кожного разу переробляти таблицю, якщо вона залежить
від незмінного каталогу? Спеціальна мовна модель все одно опрацьовуватиме каталог і може
підготувати таблицю, яка буде використовуватися. Усі оновлення та зміни каталогу просто
приводитимуть до оновлень і змін у постійній таблиці».

ЩО ЦЕ МІНЯЄ В РІШЕННІ. Нічого в самій базі: ті самі 11 828 записів речей тими самими
полями, ті самі лічильники й той самий слід. Міняється, ДЕ її рахують. Доти перший збір
сесії будував базу (`фід_каталог.прочитати_каталог`: слот, тип, колір, lab, вікно, крій,
матеріал кожної речі) у Pyodide на головному потоці — ~24 с на стенді, поки жінка чекала.
Тепер базу будує збирач (`build_артефакт.py`) і кладе цим файлом у вантаж, а продукт її
відновлює (`база`).

ЧОМУ РІЗНИЦЕЮ ДО ФІДУ, А НЕ ЦІЛИМ ЗАПИСОМ. Фід (XML) лишається у вантажі: його читає
картка показу (`міст_опис.показ` — параметри, опис, фото, назви), і розбирається він раз
на сесію (`фід_розбір.офери_фіду`). Запис бази бере з оферу кілька полів без змін (id,
group_id, назва, ціна, url, фото, магазин…), тож тут лежить лише ВИВЕДЕНЕ кодом і змінене
проти оферу — стовпчиками, з іменем поля один раз. Виміряно на повному каталозі: повна
база — 2.85 МБ gzip, ця різниця — ~0.8 МБ; фід + таблиця вміщаються в стелю збірки.

ФОРМАТ (версія 1) — JSON у gzip:
  версія; фід_ім — ім'я фіду, з якого збудовано; ключ — див. «КЛЮЧ» нижче;
  записи — [№ оферу] у порядку бази (офер — елемент `фід_розбір.офери_фіду`);
  імена — імена полів записів, кожне один раз;
  поля — {ім'я: стовпчик}: {"щ": [...]} — щільний (значення на кожен запис; `ПРОПУСК` —
         у цього запису значення з оферу або поля нема) або {"і": [№ запису], "з": [...]};
         рядок, що є елементом `фото` свого оферу, лежить посиланням [`ПОСИЛАННЯ`, "фото", №]
         (так `фото_опису`: адреса кадру, яку описали жнива, — одна з фото речі);
  порядки / порядок — ключі запису по черзі ([[№ імені]]) і номер набору на кожен запис:
         словник відновлюється з тим самим порядком ключів, що на льоту (далі по течії
         записи йдуть у JSON пакета, і порядок там видно);
  кортежі — {поле: [шлях]}: де запис на льоту несе кортеж, а JSON дав би список (lab,
         вікно, місця…); "*" у шляху — будь-який елемент списку чи кортежу;
  лічильники (+ кортежі_лічильників, порядок_бази) — офферів, у_слотах, без_слота, збої,
         розкиди, відкинуто — у тому порядку ключів, що `_прочитати_каталог`;
  слід — записи сліду, які лишила побудова (R-FEED-01, R-FEED-02): дописуються в слід
         виклику тим самим `фід_каталог._дописати_слід_бази`, що й з кеша бази;
  тип_кеш — усе, що побудова лишила в `фід_слот.ТИП_КЕШ`: [№ оферу, слот, тип], де ключ
         (категорія, назва суду) — того оферу, або [категорія, назва, слот, тип]. Далі по
         течії тип питають уже в ЗАПИСУ бази (`різноманітність_пулу`, `міст_опис.
         _поля_укладки`), а в записі нема `параметри`, з яких тип рахувався; на льоту
         відповідь давав кеш, наповнений побудовою з оферу, — без нього тип рахувався б із
         запису й міг би розійтись.

ПОЛЯ РОЗБОРУ КАТАЛОГУ (`каталог_розбір.py`, окремий наряд) лягають сюди новими
стовпчиками тієї самої форми: відновлення бере всі стовпчики, які є, і нового коду в
продукті для них не треба.

КЛЮЧ І ЗАСТАРІЛІСТЬ. Таблиця чесна рівно доти, доки збігаються входи, з яких її збудовано,
і всі вони лежать у ключі md5-сумами:
  фід — байти XML (після чистки збирачем);
  код — кожен модуль статичного замикання `фід_каталог` (той, хто будує базу, і все, що він
        може покликати): ім'я → md5 ТИХ байтів, що їдуть у вантаж;
  дані — кожен файл поруч, який побудова відкривала або питала, крім фіду й кеша кольорів
        (збагачення, показність, виміри кадрів…; записано перехопленням `open` і `os.stat`,
        а не списком руками); файл, якого не було, лежить у ключі як відсутній (None) —
        з'явиться (виміри кадрів із ноутбука), і таблиця застаріє, а не вживеться мовчки;
  умови — `ліміт_фото` 0 і порожній кеш кольорів (так кличе продукт).
Перед відновленням продукт звіряє ключ з тим, що лежить поруч (`база`). Розбіжність —
таблицю НЕ вжито, база будується на льоту, як доти, а що саме розійшлось, лягає в
`СТАН` і звідти в `мета.таблиця_каталогу` виходу `запити` — у звіт власника.
Збирач тримає таблицю в кеші (`ТЕКА_КЕША`) за тим самим ключем і будує наново лише тоді,
коли змінився фід, код чи дані.
"""
import gzip as _gz
import hashlib as _hl
import json as _json
import os as _os
import фід_розбір as _ФР
import фід_слот as _ФС

ІМ = "каталог_таблиця.json.gz"
ВЕРСІЯ = 1
ПРОПУСК = "\u0000пропуск"          # у щільному стовпчику: значення не з таблиці
ПОСИЛАННЯ = "\u0000↑"             # [ПОСИЛАННЯ, поле оферу, №]: значення — елемент списку оферу
ТЕКА_КЕША = ".таблиця_каталогу"    # кеш збирача поруч із джерелами (у .gitignore)

# Стан останнього звертання продукту до таблиці — для `мета.таблиця_каталогу` (звіт
# власника). `стан`: «вжито» | «нема» | «застаріла» | «зіпсована»; `чому` — що саме.
СТАН = {"стан": "не питали"}


def _md5(дані):
    """md5 байтів, hex."""
    return _hl.md5(дані).hexdigest()


def _md5_файла(шлях):
    """md5 файла частинами — фід важить 50 МБ."""
    х = _hl.md5()
    with open(шлях, "rb") as f:
        for шматок in iter(lambda: f.read(1 << 20), b""):
            х.update(шматок)
    return х.hexdigest()


def модулі_побудови(тека):
    """Статичне замикання імпортів від `фід_каталог` у межах теки — код, що будує базу.

    Той самий AST-підхід, що `склад.модулі_системи` (регулярка брала лише перше ім'я
    рядка), але від іншого кореня й без звірки складу продукту. Імпорти всередині функцій
    теж ідуть у замикання: побудова кличе частину модулів ліниво."""
    import ast as _ast
    мод = {f[:-3] for f in _os.listdir(тека) if f.endswith(".py")}
    треба, край = set(), {"фід_каталог"}
    while край:
        м = край.pop()
        треба.add(м)
        дерево = _ast.parse(open(_os.path.join(тека, м + ".py"), encoding="utf-8").read())
        for в in _ast.walk(дерево):
            if isinstance(в, _ast.Import):
                край |= {а.name.split(".")[0] for а in в.names} & мод - треба
            elif isinstance(в, _ast.ImportFrom) and в.level == 0 and в.module:
                край |= {в.module.split(".")[0]} & мод - треба
    return sorted(треба)


# ── КОРТЕЖІ: ДЕ JSON ДАВ БИ СПИСОК ──────────────────────────────────────────
def шляхи_кортежів(v, шлях=()):
    """Шляхи всередині значення, де стоїть кортеж; індекси списків — "*"."""
    if isinstance(v, tuple):
        yield шлях
        for x in v:
            yield from шляхи_кортежів(x, шлях + ("*",))
    elif isinstance(v, list):
        for x in v:
            yield from шляхи_кортежів(x, шлях + ("*",))
    elif isinstance(v, dict):
        for к, x in v.items():
            yield from шляхи_кортежів(x, шлях + (к,))


def _глибші(шляхи):
    """Власні префікси шляхів кортежів: нижче за шлях, якого тут нема, кортежів уже не лишилось."""
    return {ш[:н] for ш in шляхи for н in range(len(ш))}


def _у_кортежі(v, шляхи, шлях=(), глибші=None):
    """Списки на `шляхах` — назад у кортежі (зворотне до JSON). Гілку, під якою кортежів нема
    (`глибші` — префікси шляхів), віддає як є: вона з розібраного JSON і нікому більше не потрібна."""
    if глибші is None:
        глибші = _глибші(шляхи)
    if isinstance(v, list):
        if шлях in глибші:
            v = [_у_кортежі(x, шляхи, шлях + ("*",), глибші) for x in v]
        return tuple(v) if шлях in шляхи else v
    if isinstance(v, dict):
        if шлях in глибші:
            return {к: _у_кортежі(x, шляхи, шлях + (к,), глибші) for к, x in v.items()}
        return v
    return v


_НЕЗМІННІ = frozenset((str, int, float, bool, type(None)))


def _копія(v):
    """Значення з оферу — у запис власною копією: запис далі по течії дописують, а офер
    той самий бачить картка показу. Незмінне (рядок, число, None) не копіюється."""
    т = type(v)
    if т is list:
        return [x if type(x) in _НЕЗМІННІ else _копія(x) for x in v]
    if т is dict:
        return {к: (x if type(x) in _НЕЗМІННІ else _копія(x)) for к, x in v.items()}
    return v


def однакові(a, b):
    """Рівність із типами й порядком ключів: кортеж ≠ список, 1 ≠ 1.0 ≠ True."""
    if type(a) is not type(b):
        return False
    if isinstance(a, dict):
        return list(a) == list(b) and all(однакові(a[к], b[к]) for к in a)
    if isinstance(a, (list, tuple)):
        return len(a) == len(b) and all(однакові(x, y) for x, y in zip(a, b))
    return a == b


def ключ(шлях_фіду, тека, байти_модулів=None, файли_даних=()):
    """Ключ таблиці: md5 фіду, коду побудови, даних і умови виклику (див. докстрінг модуля)."""
    мод = {}
    for м in модулі_побудови(тека):
        дані = (байти_модулів or {}).get(м)
        if дані is None:
            with open(_os.path.join(тека, м + ".py"), "rb") as f:
                дані = f.read()
        мод[м] = _md5(дані)
    # файл, якого нема, — None: побудова його питала й не знайшла (див. `build_артефакт.зібрати_таблицю_каталогу`)
    return dict(фід=_md5_файла(шлях_фіду), код=мод,
                дані={_os.path.basename(ф): (_md5_файла(ф) if _os.path.isfile(ф) else None)
                      for ф in sorted(set(файли_даних))},
                умови=dict(ліміт_фото=0, кеш_кольорів="{}"))


def записати(т, шлях):
    """Таблиця у файл — детерміновано (ключі по черзі, gzip без часу), як решта вантажу."""
    сирі = _json.dumps(т, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    with open(шлях, "wb") as f:
        with _gz.GzipFile(fileobj=f, mode="wb", compresslevel=9, mtime=0) as г:
            г.write(сирі)


# ── ВІДНОВЛЕННЯ (ПРОДУКТ) ─────────────────────────────────────────────────────
def позначка(v):
    """Чи має значення форму службової позначки таблиці (тоді кодувати його не можна)."""
    return ((isinstance(v, str) and v == ПРОПУСК)
            or (isinstance(v, list) and len(v) == 3 and v[0] == ПОСИЛАННЯ))


def відновити(т, офери):
    """`відновити_кроками`, доведене до кінця за один виклик (збирач, проби, не-Pyodide)."""
    return _ФР.ганяти(відновити_кроками(т, офери))


def відновити_кроками(т, офери):
    """База з таблиці й оферів фіду: {каталог, офферів, у_слотах, без_слота, збої,
    розкиди, відкинуто} — той самий словник, що `_прочитати_каталог`.

    Генератор: `yield`, коли `пора()` (див. `фід_розбір.ганяти`, рядок 5841)."""
    н = len(т["записи"])
    імена = т["імена"]
    стовпці = {}
    for к, ст in т["поля"].items():
        if "щ" in ст:
            стовпці[к] = ст["щ"]
        else:
            с = [ПРОПУСК] * н
            for і, з in zip(ст["і"], ст["з"]):
                с[і] = з
            стовпці[к] = с
    кортежі = {к: {tuple(ш) for ш in шш} for к, шш in т["кортежі"].items()}
    глиб = {к: _глибші(шш) for к, шш in кортежі.items()}
    порожньо = [ПРОПУСК] * н
    # поля запису одного порядку: (ім'я, стовпець, шляхи кортежів, їх префікси) — без пошуку за іменем на кожне значення
    порядки = [[(к, стовпці.get(к, порожньо), кортежі.get(к), глиб.get(к)) for к in (імена[к] for к in п)]
               for п in т["порядки"]]
    записи = []
    for і, п in enumerate(т["записи"]):
        o = офери[п]
        r = {}
        for к, ст, шл, гл in порядки[т["порядок"][і]]:
            v = ст[і]
            т_ = type(v)
            if т_ is str:
                if v == ПРОПУСК:
                    v = _копія(o[к])
                    т_ = type(v)
            elif т_ is list and len(v) == 3 and v[0] == ПОСИЛАННЯ:
                v = o[v[1]][v[2]]
                т_ = type(v)
            r[к] = _у_кортежі(v, шл, (), гл) if шл is not None and (т_ is list or т_ is dict) else v
        записи.append(r)
        if _ФР.пора():
            yield
    б = {"каталог": записи}
    for к, v in т["лічильники"].items():
        б[к] = _у_кортежі(v, {tuple(ш) for ш in т["кортежі_лічильників"].get(к) or []})
    # порядок ключів бази — як у `_прочитати_каталог`
    return {к: б[к] for к in т["порядок_бази"]}


def тип_кеш(т, офери):
    """Записи `фід_слот.ТИП_КЕШ`, які лишила побудова: [((категорія, назва, слот), тип)]."""
    вих = []
    for з in т["тип_кеш"]:
        if len(з) == 3:
            o = офери[з[0]]
            вих.append(((str(o.get("категорія", "")), _ФС.назва_суду(o), з[1]), з[2]))
        else:
            вих.append(((з[0], з[1], з[2]), з[3]))
    return вих


def _таблиця_поруч(тека):
    """Шлях до таблиці у вантажі (поруч із `feed.py`) або None."""
    ш = _os.path.join(тека, ІМ)
    return ш if _os.path.exists(ш) else None


