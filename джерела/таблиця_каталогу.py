def з_кеша_збирача(шлях_фіду, тека, байти_модулів):
    """Таблиця з кеша збирача, коли її ключ збігся з поточними фідом, кодом і даними; або None."""
    ш = _os.path.join(тека, ТЕКА_КЕША, ІМ)
    if not _os.path.exists(ш):
        return None
    try:
        with _gz.open(ш, "rt", encoding="utf-8") as f:
            т = _json.load(f)
    except (OSError, ValueError):
        return None
    if т.get("версія") != ВЕРСІЯ:
        return None
    дані = [_os.path.join(тека, ім) for ім in ((т.get("ключ") or {}).get("дані") or {})]
    return т if т.get("ключ") == ключ(шлях_фіду, тека, байти_модулів, дані) else None


def в_кеш_збирача(т, тека):
    """Таблиця в кеш збирача: наступна збірка з тим самим ключем її вже не будує."""
    _os.makedirs(_os.path.join(тека, ТЕКА_КЕША), exist_ok=True)
    записати(т, _os.path.join(тека, ТЕКА_КЕША, ІМ))
