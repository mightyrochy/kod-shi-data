_СМІТТЯ_НАЗВИ = re.compile(r"^\s*(?:!\[\s*image\s*\d*\s*:?\s*|картинка\s+|зображення\s+|фото\s+)+", re.I)

ЦІНА_СТЕЛЯ = 1_000_000.0   # грн; вище — склейка полів жниварки, не ціна

def _чиста_ціна(текст):
    """Ціна з рядка фіду як число; нечислове — 0.0, а вище `ЦІНА_СТЕЛЯ` — теж 0.0,
    бо це склейка полів жниварки, не ціна (нуль тут читається як «ціни нема»)."""
    try:
        v = float(str(текст or "0").replace(",", ".").strip() or 0)
    except ValueError:
        return 0.0
    return 0.0 if v >= ЦІНА_СТЕЛЯ else v


def _чиста_назва(назва):
    """Знімає alt-текстові та markdown-префікси жниварки з назви товару."""
    n = _СМІТТЯ_НАЗВИ.sub("", str(назва or ""))
    n = re.sub(r"\]\s*\(.*?\)\s*$", "", n)          # хвіст markdown-картинки «](url)»
    return n.strip()                                # порожньо = назви не було, лише сміття


