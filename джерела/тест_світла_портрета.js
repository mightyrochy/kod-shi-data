/* Без мережі й фото: дія екрана, вимір через синтетичну відповідь моста, мовний шар і перемикання профілю.
   node джерела/тест_світла_портрета.js [шлях до іншої теки джерела для порівняння] */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const корінь = process.argv[2] || __dirname;
const файл = ім => fs.readFileSync(path.join(корінь, ім), 'utf8');
const макет = файл('показ.html');
assert.match(макет, /id="ф-блок">[\s\S]*?id="ф-портрет"[\s\S]*?class="підказка">Щойно додаси портрет/);

const вузли = new Map();
const вузол = () => ({textContent: '', hidden: false, addEventListener(){}, closest(){ return null; }, setAttribute(к, з){ this[к] = з; }});
for (const [, ід] of макет.matchAll(/\bid="([^"]+)"/g)) вузли.set(ід, вузол());
const підказка = вузол(), попередження = () => вузли.get('ф-світло-портрета');
підказка.before = в => { вузли.set(в.id, в); в.біля_підказки = true; };
вузли.get('ф-блок').querySelector = с => с === ':scope > .підказка' ? підказка : null;

const нерівне = {стан: 'поза_воротами', причини: ['portrait_uneven_light'], шкіра: null, волосся: null, очі: null};
const вимір = {стан: 'вимір', причини: [], шкіра: {hex: '#b78d77'}, волосся: {hex: '#30261f'}, очі: {hex: '#546253'}};
const зчитано = {стан: 'готово', шкіра: ['#a47962'], волосся: ['#312522'], очі: '#5a654a', зони: {лоб: {}}};
const переклад = 'На твоєму фото світло падає лише на один бік обличчя. Зроби портрет обличчям до вікна.';
let відповідьВиміру = нерівне, порада = переклад, дочекались, мовніВиклики = 0;
const контекст = vm.createContext({
  document: {getElementById: ід => вузли.get(ід), querySelectorAll: () => [], createElement: вузол},
  текстЖінціП: (в, т) => { в.textContent = т; }, своїЕкрануП: () => ({}),
  location: {protocol: 'file:'}, МІСТ_П: {}, читатиКв: async () => ({}), ключФото: в => в,
  блобВБазу: async () => 'synthetic', модельРукиП: async () => '{}',
  кадрівНеДійшлоП(){}, дійшлоКадрівП: () => ({жодного: false}), пікселіРечіП: async () => ({}),
  містП: async (дія, вхід) => { assert.equal(дія, 'колір'); return вхід.виміряти ? відповідьВиміру : зчитано; },
  повідомленнямП: async (вхід, адреса) => {
    мовніВиклики++;
    assert.equal(адреса, 'intro.portrait');
    assert.equal(вхід.портрет.kind, 'portrait_unmeasured');
    assert.equal(вхід.портрет.statements[0].code, відповідьВиміру.причини[0]);
    if (порада instanceof Promise) дочекались();
    return {тексти: {портрет: await порада}};
  },
  завершитиДіюЯдра(){}, збійЖінціП: (в, к, е) => { throw e; },
  дочекатисьЧатуП: async () => true, зберегтиЧернетку: async () => {},
  оновитиФотоП: async () => {}, відновитиВипадок: async () => {}, оновитиСценарії: async () => {},
  новаОцінкаП: () => ({}), ВИКЛИКИ_РОЗМОВИ_П: [], ОЦ: {}, режим(){}, режимЕкрана: () => 'профіль',
  копіювати: () => true
});
const виконати = дії => vm.runInContext(дії, контекст);
for (const ім of ['екран/ядро.js', 'профілі.js', 'кольори.js', 'екран/профіль.js', 'екран/кольори.js']){
  vm.runInContext(файл('показ/' + ім), контекст, {filename: ім});
}
виконати(`ПРОФІЛІ = [{ід: 'а'}, {ід: 'б'}]; АКТИВНИЙ = 'а';
  писатиКв = async () => {}; писатиАктивний = async () => {}; читатиАктивний = async () => { КОЛІР = {}; };
  зрізПрофіляП = () => ({}); Екран.змінити({вхід: true});`);
const зчитати = () => виконати("Екран.відЖінки('кольори-зчитати')");
const перемкнути = ід => виконати("Екран.відЖінки('профіль-обрати', null, {value: " + JSON.stringify(ід) + "})");
const джерелоКольорів = () => виконати('КОЛІР.походження');
const безПопередження = () => { assert.equal(попередження().textContent, ''); assert.equal(підказка.hidden, false); };

(async () => {
  await зчитати();
  assert.equal(джерелоКольорів(), 'оцінка_моделі');
  assert.equal(виконати('КОЛІР.шкіра'), зчитано.шкіра[0]);
  assert.ok(попередження(), 'На кроці портрета немає попередження; нижній рядок: ' + вузли.get('кол-стан').textContent);
  assert.ok(попередження().біля_підказки);
  assert.equal(попередження().role, 'status');
  assert.equal(підказка.hidden, true);
  assert.match(попередження().textContent, /оцінка моделі, не вимір/);
  assert.ok(попередження().textContent.includes(переклад));
  assert.ok(!вузли.get('кол-стан').textContent.includes(переклад));
  assert.equal(мовніВиклики, 1);

  порада = undefined;
  await зчитати();
  assert.match(попередження().textContent, /оцінка моделі, не вимір.*нерівномірно.*обличчям до вікна без прямого сонця/);
  виконати("Екран.відЖінки('кольори-копіювати')");
  assert.match(попередження().textContent, /нерівномірно/);

  відповідьВиміру = вимір;
  await зчитати();
  безПопередження();
  assert.equal(джерелоКольорів(), 'вимір');
  assert.equal(виконати('КОЛІР.шкіра'), вимір.шкіра.hex);
  assert.equal(мовніВиклики, 2);

  відповідьВиміру = {...нерівне, причини: ['portrait_hair_unmeasured']};
  порада = 'На фото не вдалося виміряти колір волосся.';
  await зчитати();
  безПопередження();
  assert.match(вузли.get('кол-стан').textContent, /не вдалося виміряти колір волосся/);

  відповідьВиміру = нерівне;
  let завершитиПереклад;
  порада = new Promise(рез => { завершитиПереклад = рез; });
  const почавсяПереклад = new Promise(рез => { дочекались = рез; });
  const запит = зчитати();
  await почавсяПереклад;
  assert.match(попередження().textContent, /обличчям до вікна/);
  assert.equal(await перемкнути('б'), true);
  безПопередження();
  завершитиПереклад(переклад);
  await запит;
  безПопередження();
  assert.equal(джерелоКольорів(), undefined);
  assert.equal(await перемкнути('а'), true);
  безПопередження();
  console.log('ОК: переклад, запасна порада, успішне перечитання, інша причина, зміна профілю і запізнілий переклад');
})().catch(помилка => { console.error(помилка); process.exitCode = 1; });
