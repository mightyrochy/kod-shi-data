"""ТЕМПЕРАТУРА ПАЛІТРИ: підтон особи → тепла/холодна версія нейтралей і нахил акценту.
ТЕМП_НЕЙТРАЛІ (карта тепла/холодна/нейтральна/оливкова → дуга нейтралі, метал,
приклади), `температура` (R-CHEV-08: `intent` як параметр мети замість сезону; дві
ортогональні осі впевненості — сила підтону й надійність виміру; знак осі береться
лише там, де він є виміром, бік — з елісітації) і сама елісітація: ЕЛІСІТАЦІЯ_СЛОВНИК
(один реєстр відповідей на три канали — метал, білий, нейтралі), `_відповідь_каналу`,
`тепло_з_елісітації` (R-PC-04: стимульна елісітація — первинне джерело, фото —
assist; голос і утримання — дві різні речі).

ЧОМУ ОКРЕМИЙ ФАЙЛ (20.09.2026, хвиля стандарту, СТАНДАРТ_КОДУ п.16: файл
≤ 1 500 рядків). `palette.py` виріс до 2 746 рядків; тіло розділено на вісім модулів
`палітра_*` ЧИСТИМ перенесенням, а `palette` лишився фасадом із реекспортом кожного
імені. Елісітація стоїть в одному файлі з `температура`, бо та кличе
`тепло_з_елісітації` на кожному виклику: бік класу (тепла/холодна) береться з
відповідей людини, а не з камери. Читають цей модуль `палітра_нейтраль`
(`нейтраль_якір` будує вікно b* на `температура` і на тій самій елісітації — один
свідок на одне питання) і `палітра_специфікація` (`розвилка_специфікацій` кладе
`температура` у вихід).

ЩО ТУТ (рядки — за `palette.py` до поділу, коміт efa403e): ТЕМП_НЕЙТРАЛІ,
`температура` (374–532); _ЕЛ_НЕЙТРАЛЬНІ, ЕЛІСІТАЦІЯ_СЛОВНИК, `_відповідь_каналу`,
`тепло_з_елісітації` (1909–2008). Порядок у файлі — як був: `температура` стоїть
перед `тепло_з_елісітації` і кличе її під час виконання, не на імпорті.

РЕБРА. Імпортує лише зовнішнє (`colorspace`, `реєстр_правил`); жодного модуля
`палітра_*` і не фасад."""
from colorspace import reliability, MIN_TO_EMIT
import реєстр_правил as _РЕЄСТР


# ─── ТЕМПЕРАТУРА: підтон особи -> тепла/холодна версія палітри ──────────────────
# СВІДОМО порушує «спершу вимір» (дозволено). Тепер на CONTINUUM-МАГНІТУДІ (тепло_сила з
# colorspace), а не на hue-band-класифікаторі. ДВІ ОРТОГОНАЛЬНІ осі впевненості, окремо:
#  (A) СИЛА підтону = |тепло_сила| — наскільки людина взагалі тепла/холодна (позиція на
#      континуумі). Є ЗАВЖДИ, самовідносна (h° від центру 57°, розкид 12° — виміряні числа);
#      калібрування проти драпіровки НЕ треба. Біля центру = ЩИРО нейтральна, це факт, не провал.
#  (B) НАДІЙНІСТЬ виміру = reliability.undertone>=MIN_TO_EMIT. b* найчутливіший до балансу білого
#      (фото=овертон+світло, ShadeCompass/ColorisLab) -> абсолютна сила надійна лише на протоколі.
# Діяти впевнено = ОБИДВІ високі. Це знімає стару проблему «дефолтного відра»: раніше 'тепле'
# було відром низької впевненості; тепер низька впевненість = мала МАГНІТУДА (близько нейтралі),
# а не клас. Впорскуємо в запит лише коли обидві осі дозволяють; інакше не форсуємо (не перекіс).
# КОМПОНУЄТЬСЯ, не конкурує: контраст дає структуру світлоти, схема — відношення тонів,
# пропорція — частки, температура обирає ТЕПЛУ/ХОЛОДНУ версію нейтралей і нахил акценту.
# РАНГ осей контестований: одні кладуть підтон першим (alyssa), інші value/chroma першими
# (stylementor) — тому температура НЕ домінує над контраст-віссю, а множиться на неї.
ТЕМП_НЕЙТРАЛІ = {          # дуги тону — T3-конвенційні межі; ахроматика (C≈0) температуро-гнучка
 "тепла":      dict(нейтраль_дуга=(40, 95),   метал="золото",
    приклади="кемел, беж, теплий сірий, олива, вершковий/off-white",
    акцент_нахил="теплий бік тону (жовто-червоний)", уникати="справжній холодний білий"),
 "холодна":    dict(нейтраль_дуга=(220, 280), метал="срібло",
    приклади="нейві, холодний сірий, справжній білий, чорний",
    акцент_нахил="холодний бік тону (синій)", уникати="жовтувато-теплий беж"),
 "нейтральна": dict(нейтраль_дуга=None,        метал="обидва",
    приклади="і теплі, і холодні нейтралі", акцент_нахил="без нахилу", уникати="—"),
 # МЕТАЛ ОЛИВИ — ДЕФОЛТ, А НЕ ПЕРЕЛІК (Н-V04-012). Тут стояв рядок «золото
 # (частіше), але буває холодна олива -> срібло»: на питання людини «золото
 # чи срібло?» реєстр відповідав реченням про те, що буває по-різному, і це
 # речення їхало в `bridge._основи` (bridge.py:414) як фолбек вибору. Лишаємо
 # «золото» дефолтом БЕЗ елісітації; з елісітацією його перекриває бік,
 # обраний людиною (див. `температура`, блок під `рек = ТЕМП_НЕЙТРАЛІ[клас]`).
 "оливкова":   dict(нейтраль_дуга=(50, 110),  метал="золото",
    приклади="оливкові й теплі нейтралі; при холодній оливі — приглушені холодні",
    акцент_нахил="приглушено (олива = синьо-жовте перетягування, не чисто тепле)",
    уникати="справжній холодний білий (сіріє); чистий яскравий (мутніє)"),
}
# R-CHEV-08 — дубль `palette.температура`: `intent` як параметр мети замість сезону.
def температура(F, source="uncontrolled", intent="conventional", самозвіт=None):
    """Підтон особи -> температура палітри. Споживає CONTINUUM-МАГНІТУДУ (тепло_сила з colorspace,
    замість cos(h-60)). ДВІ ОРТОГОНАЛЬНІ осі впевненості, окремо:
      (A) сила підтону = |тепло_сила| — наскільки людина взагалі тепла/холодна. Є ЗАВЖДИ,
          самовідносна (відстань h° від нейтрального центру), калібрування проти драпіровки НЕ треба.
          Біля центру людина ЩИРО нейтральна — це факт, не провал виміру.
      (B) надійність виміру = reliability(source).undertone >= MIN_TO_EMIT. b* найчутливіший до
          балансу білого, тож абсолютна сила надійна лише на протокол-захваті (uncontrolled=0.15).
    Впорскує обмеження в запит ЛИШЕ коли ОБИДВІ високі; інакше радить і деградує до питання.
    Олива — окрема 2D вісь (p_olive), не низька магнітуда: green-каст через усі глибини."""
    rel = reliability(source)["undertone"]
    надійно = rel >= MIN_TO_EMIT
    sk = F.get("шкіра", {})
    сила = sk.get("тепло_сила")               # continuum-магнітуда (замість cos(h-60))
    p_ol = sk.get("олива_член", 0.0) or 0.0   # плоскісна олива (warm+muted у площині a*b*)
    conv = _РЕЄСТР.стриманий_намір(intent)   # K-PER-00: comfort_first / context_optimal — теж конвенція
    дегр = ("вимкнено -> спитати золото/срібло та справжній-білий/збіжений; вести value+chroma "
            "(робастніші за підтон до балансу білого)")
    if сила is None:
        return dict(придатно=False, впорскувати_в_запит=False,
            причина="нема тепло_сили в профілі шкіри (colorspace не дав магнітуду)",
            деградація=дегр, ранг="value/chroma робастніші — вести ними")
    сила_абс = abs(сила)
    # ── ЗНАК ОСІ БЕРЕТЬСЯ ЛИШЕ ТАМ, ДЕ ВІН Є ВИМІРОМ (08.09.2026) ────────────
    # ЩО ТУТ СТОЯЛО. Клас рахувався за знаком `тепло_сила` беззастережно. А
    # `colorspace._температура_шкіри` цей самий знак ПРИДУШУЄ і каже прямо:
    # «не стверджується (вісь одностороння на цій популяції)».
    #
    # Підстава придушення виміряна власним приладом проєкту (`audit_anchors.py`,
    # перевірка B) і надрукована ним же:
    #     європейський діапазон тону шкіри (Weatherall & Coombs 1992) 54.0–77.8°
    #     холодна 0.0 % · нейтральна 37.8 % · тепла 62.2 %
    #     ✗ ПОРОЖНЯ СТОРОНА
    # Межа «холодна» стоїть на h < 51.0°, куди діапазон цільової популяції не
    # заходить ЗОВСІМ. Отже на українській користувачці «холодна» не рідкісна —
    # вона неможлива за побудовою.
    #
    # Прилад це знайшов, `colorspace` послухався, `palette` ні. І саме тут ціна
    # найвища: клас іде в `ТЕМП_НЕЙТРАЛІ` → рекомендовані нейтралі, МЕТАЛ
    # (золото/срібло) і нахил акценту, а `впорскувати_в_запит` кладе їх у запит
    # до каталогу. Тобто непідтверджений знак ставав фільтром речей.
    #
    # ЩО ЗАМІСТЬ. Рівно те, що вже робить `colorspace` і що обіцяє рядок
    # `деградація` цього ж файла: магнітуда лишається, ЗНАК не стверджується,
    # олива виживає (це окремий регіон площини a*b*, не знак), а бік беруть із
    # ЕЛІСІТАЦІЇ — золото/срібло й білий, які від камери не залежать (R-PC-04).
    # `тепло_з_елісітації` для цього вже написана й доти не викликалася нізвідки.
    знак_придатний = (F.get("шкіра") or {}).get("вісь_знак_придатний")
    ел = тепло_з_елісітації(**{k: (самозвіт or {}).get(k)
                               for k in ("білий", "метал", "нейтралі")})
    знак_з_елісітації = (ел.get("w") is not None and ел.get("впевненість", 0) >= 0.5
                         and abs(ел["w"]) > 0.0)
    if p_ol >= 0.33:
        клас, джерело_класу = "оливкова", "олива — окремий регіон площини a*b*, не знак осі"
    elif знак_придатний is False and not знак_з_елісітації:
        клас = "нейтральна"
        джерело_класу = ("знак осі підтону НЕ стверджується: на оголошеній популяції "
                         "одна сторона порожня (audit_anchors B). Магнітуда лишається, "
                         "бік — питання до людини")
    elif знак_з_елісітації:
        клас = "тепла" if ел["w"] > 0 else "холодна"
        джерело_класу = "елісітація (%s, впевненість %.2f) — не залежить від камери" % (
            ел.get("нота") or ел.get("джерело"), ел.get("впевненість") or 0.0)
    else:
        клас = ("тепла" if сила > 0.5 else "холодна" if сила < -0.5 else "нейтральна")
        джерело_класу = "знак тепло_сили з фото (вісь двостороння на цій популяції)"
    рек = ТЕМП_НЕЙТРАЛІ[клас]
    # ── КЛАС І БІК — ДВІ РІЗНІ РЕЧІ (Н-V04-012, 11.09.2026) ──────────────────
    # `colorspace.олива_основа` формулює це сама: «олива/золото перекриваються ->
    # членство мʼяке; вирішення=елісітація». Тобто олива каже, В ЯКОМУ РЕГІОНІ
    # площини a*b* людина стоїть, але не каже, який бік їй личить, — і саме там,
    # де вона мовчить, проєкт домовився питати людину (R-PC-04).
    #
    # ЩО БУЛО. Гілка `p_ol >= 0.33` стоїть першою (і правильно: олива — регіон, не
    # знак), але разом із класом вона забирала й МЕТАЛ з `ТЕМП_НЕЙТРАЛІ['оливкова']`.
    # Наслідок вимірний: самозвіт «срібло» і самозвіт «золото» давали побайтово
    # однаковий метал — дві заповнені картки не міняли нічого.
    #
    # ЩО СТАЛО. Клас лишається оливковим (міняти умови місцями наосліп означало б
    # зруйнувати олив'яну вісь, яку `colorspace` тримає окремо), а бік беруть поля,
    # які БІК і виражають: `метал` і `акцент_нахил`. `нейтраль_дуга` і `приклади`
    # лишаються оливковими — їх тримає регіон, а не знак.
    if клас == "оливкова" and знак_з_елісітації:
        _бік = "тепла" if ел["w"] > 0 else "холодна"
        рек = dict(рек, метал=ТЕМП_НЕЙТРАЛІ[_бік]["метал"],
                   акцент_нахил=ТЕМП_НЕЙТРАЛІ[_бік]["акцент_нахил"])
        джерело_класу += ("; олива — регіон площини; бік металу — з елісітації "
                          "(не залежить від камери)")
    строгість = [dict(назва="температура-матч",
        коли="дефолт під conventional: нейтраль-якір і нахил акценту в температурі особи",
        основа="лестити обличчю (конвергентна карта тепла/холодна->нейтраль)")]
    строгість.append(dict(назва="вибір-понад-температуру",
        коли=(f"під intent={intent}: свідомо поза температурою (експресія)" if not conv
              else "навіть під conventional — якщо користувач любить колір поза температурою"),
        основа="дисент (Skin Inc.: 'кожен може носити будь-які тони') + перевага користувача "
               "(Healthline: 'облиш правила'); не гейт. Поза обличчям / як акцент — безпечніше"))
    # ВПОРСКУЄМО лише коли ОБИДВІ осі високі: надійність І достатня магнітуда І є дуга.
    # Олива при p_ol>=0.5 впорскується незалежно від сили (це окрема певна вісь).
    магн_дозволяє = (сила_абс >= 0.5) or (клас == "оливкова" and надійно)
    # Знак із елісітації камери не потребує: він і є той канал, на який показує
    # `деградація`. Знак, придушений як невимір, у запит не йде взагалі.
    # Олива — НЕ твердження про знак: `colorspace` тримає її навіть тоді, коли знак
    # придушує («undertone = оливковий», якщо член ≥ 0.33). Тому вона впорскується
    # незалежно від придатності знака — інакше придушення знака мовчки з'їдало б
    # окрему вісь, яка від нього не залежить.
    впорск = (рек["нейтраль_дуга"] is not None) and (
        знак_з_елісітації
        or (клас == "оливкова" and надійно)
        or (надійно and магн_дозволяє and знак_придатний is not False))
    return dict(придатно=True, клас=клас, тепло_сила=сила, сила_підтону=round(сила_абс, 2),
        джерело_класу=джерело_класу, знак_осі_придатний=знак_придатний, елісітація=ел,
        впорскувати_в_запит=впорск,
        нейтраль_дуга=рек["нейтраль_дуга"], метал=рек["метал"], акцент_нахил=рек["акцент_нахил"],
        приклади_нейтралей=рек["приклади"], уникати=рек["уникати"], деградація=дегр,
        строгість=строгість,
        вісь_A_сила=("висока" if сила_абс >= 0.75 else "помірна" if сила_абс >= 0.5 else
            "НИЗЬКА: близько нейтрального центру — людина ЩИРО нейтральна (не провал виміру); "
            "не форсуємо, палітру тримати нейтральною"),
        вісь_B_надійність=("ок" if надійно else
            f"низька (reliability={round(rel,2)}<{MIN_TO_EMIT}: фото=овертон+світло) -> деградація"),
        ранг="одна з трьох співважливих осей; ранг контестований — НЕ домінує над контрастом",
        провенанс="магнітуда самовідносна (h° від центру 57°, розкид 12°, виміряні) — калібрування "
                  "проти вироку не треба; карта тепла/холодна->нейтраль конвергує; дуги T3; поріг "
                  "|сила|>=0.5 як 'діяти' — продуктове рішення, не наукова даність")

# ── РЕЄСТР ВІДПОВІДЕЙ ЕЛІСІТАЦІЇ (Н-palette-2-103) ──────────────────────────
# ЩО БУЛО: три ad-hoc кортежі всередині функції, по одному на канал, з РІЗНИМИ
# наборами відповідей. Дві мовчазні дірки, обидві виміряні:
#   · «не бачу різниці» знав ЛИШЕ канал `нейтралі`. показ.html шле рівно це
#     значення і для `білий` (ДРАП_ПОЛЯ.білий), тож жива відповідь не збігалась
#     ні з чим і просто випадала: людина відповіла на три питання, а рахувалось
#     два — і саме на цьому `len(к)` стоїть уся впевненість.
#   · ключі звірялись дослівно: {'метал':'Золото'} з великої давало w=None,
#     тобто «елісітації не було» (виміряно p7.py).
# ЩО СТАЛО: один реєстр, три канали, ОДНАКОВИЙ набір нейтральних синонімів у
# кожному — асиметрія словників і була дірою, тому симетрія тут інваріант, а не
# охайність. Числа — не виміри, а КОНВЕНЦІЯ елісітації (золото↔тепле,
# срібло↔холодне; вершковий↔тепле, оптичний↔холодне; теплі/холодні нейтралі
# буквально). 0.0 — не «нема відповіді», а УТРИМАННЯ: людина дивилась і різниці
# не побачила. Це факт про неї, і він рахується (див. тепло_з_елісітації).
_ЕЛ_НЕЙТРАЛЬНІ = ("обидва", "мікс", "both", "не бачу різниці", "однаково", "не знаю")
ЕЛІСІТАЦІЯ_СЛОВНИК = {
 "метал":    dict({"золото": +1.0, "gold": +1.0, "срібло": -1.0, "silver": -1.0},
                  **{к: 0.0 for к in _ЕЛ_НЕЙТРАЛЬНІ}),
 "білий":    dict({"вершковий": +1.0, "cream": +1.0, "збіжений": +1.0,
                   "оптичний": -1.0, "optical": -1.0, "справжній": -1.0},
                  **{к: 0.0 for к in _ЕЛ_НЕЙТРАЛЬНІ}),
 "нейтралі": dict({"теплі": +1.0, "warm": +1.0, "холодні": -1.0, "cool": -1.0},
                  **{к: 0.0 for к in _ЕЛ_НЕЙТРАЛЬНІ}),
}

def _відповідь_каналу(канал, значення):
    """Знак каналу з реєстру. None — відповіді не було або її не розпізнано.
    Ключ нормалізується (обрізання + нижній регістр), бо форма шле те, що ввела
    людина, а не те, що зручно порівнювати."""
    if значення is None:
        return None
    return ЕЛІСІТАЦІЯ_СЛОВНИК.get(канал, {}).get(str(значення).strip().lower())


def тепло_з_елісітації(білий=None, метал=None, нейтралі=None):
    """R-PC-04 вимагає, щоб первинним джерелом колориту була СТИМУЛЬНА ЕЛІСІТАЦІЯ, а не
    фото. Питання вже ставить колір_образу.білі (K-COL-06): який білий кращий — оптичний чи
    вершковий, і який метал — золото чи срібло. Досі відповідь нікуди не йшла (відкрита
    петля). Тут вона стає знаком і впевненістю.

    Два канали, бо один сам себе не перевіряє: збіг двох → висока впевненість, розбіжність
    → низька (людина справді проміжна — це факт, не провал).
    Числа впевненості T3; напрям (золото↔тепле, срібло↔холодне; вершковий↔тепле) —
    конвенція елісітації, не вимір. Не вердикт: далі все одно лише вага вікна.

    ── ГОЛОС І УТРИМАННЯ — ДВІ РІЗНІ РЕЧІ (Н-palette-2-104) ──────────────────
    БУЛО: нуль-відповідь («не бачу різниці», «обидва») лежала в тому самому списку,
    що й знаки, і йшла в СЕРЕДНЄ. Наслідок вимірний: {метал:'золото'} давало w=1.0,
    а {метал:'золото', нейтралі:'не бачу різниці'} — w=0.5. Людина не сказала нічого
    проти золота; вона сказала, що в ДРУГОМУ каналі різниці не бачить, — і за це їй
    удвічі гасили канал, у якого думка є. Нота при цьому рахувала утримання як збіг
    («два канали збіглись» на трьох нулях).
    СТАЛО: `голоси` — лише ненульові відповіді, і магнітуда рахується з них одних;
    `утримання` рухає тільки ВПЕВНЕНІСТЬ (×0.85 за кожне — T3, як і решта чисел
    впевненості тут). Нуль голосів — це не знак «посередині», а відсутність знака:
    w=None, і фото лишається єдиним входом, як і до питання.
    ДРУГЕ (продуктове рішення наряду, крок 4): при незгоді знак більше не викидається
    в нуль, а важиться більшістю — 2:1 за тепле дає +0.33, не 0.0. Впевненість
    лишається 0.30: знак слабкий, але викидати його означало б стверджувати «рівно
    посередині» там, де вимір каже інше. Це змінює вихід на реальних відповідях."""
    # ТРЕТІЙ СТИМУЛ (29.08.2026). Той самий теплохолод, але на приглушених
    # нейтралях замість металу. Доданий не заради повноти: метал німий для тих,
    # хто не носить прикрас, — у них два канали вироджувались в один.
    # Цикл по реєстру замість трьох кортежів (Н-palette-2-103): канали більше не
    # можуть розійтися набором відповідей — вони всі читають один словник.
    к = [з for з in (_відповідь_каналу(кан, v)
                     for кан, v in (("метал", метал), ("білий", білий),
                                    ("нейтралі", нейтралі)))
         if з is not None]
    if not к:
        return dict(w=None, впевненість=0.0, джерело="елісітації не було",
                    питання="Який білий вам краще — оптичний (холодний) чи вершковий? "
                            "І що виграшніше біля обличчя — золото чи срібло?")
    голоси = [x for x in к if x != 0.0]
    утримань = len(к) - len(голоси)
    _хвіст = "; %d голос(ів), %d утримань" % (len(голоси), утримань)
    if not голоси:
        # Людина ДИВИЛАСЬ і різниці не побачила в жодному каналі. Це відповідь, але
        # не знак: стверджувати «рівно посередині» вона не просила. Тому w=None —
        # так само, як без елісітації, — але джерело каже, що питання вже ставили,
        # і `питання` не повертається: перепитувати нема про що.
        return dict(w=None, впевненість=0.0, джерело="елісітація (драп)",
                    нота="усі канали утримались — знак не стверджується" + _хвіст)
    # Магнітуда — СЕРЕДНЄ ГОЛОСІВ. При незгоді це зважена більшість, а не нуль
    # (крок 4 наряду): 2:1 за тепле → +0.33.
    w = sum(голоси) / len(голоси)
    if len(голоси) >= 2:
        # СПІЙМАНО 29.08.2026: перевірка дивилась лише на к[0] і к[1]. З трьома
        # каналами третій мовчки впливав на w, але не на впевненість — тобто
        # «два за, один проти» звітувало 0.75, як повна згода.
        згода = all(x > 0 for x in голоси) or all(x < 0 for x in голоси)
        впев = 0.75 if згода else 0.30
        нота = ("голоси збіглись" if згода else "голоси розійшлись — знак за більшістю") + _хвіст
    else:
        впев, нота = 0.55, "один голос" + _хвіст
    # T3: кожне утримання — ще один канал, який думки не дав; магнітуду воно не
    # рухає, але вхід від цього слабший. Множник фольклорний, як і бази вище.
    впев = round(впев * (0.85 ** утримань), 2)
    return dict(w=round(w, 2), впевненість=впев, джерело="елісітація (драп)", нота=нота)
