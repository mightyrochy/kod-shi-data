# Клас і його придатність визначає спільний запис face_features.
# Ця таблиця застосовує підтверджений клас; для невідомого рекомендації немає.
# Дуга нейтралі — бік осі тепла (`колір_тон.дуга_температури`, одне визначення тепле ↔ холодне, п.18); доти тут
# стояли власні T3-дуги тону (тепла 40–95, холодна 220–280, оливкова 50–110), а поруч `реєстр_правил` тримав інші
# межі тих самих нейтралей (дошка 13202). Ахроматика (C ≈ 0) бік не має — температуро-гнучка.
ТЕМП_НЕЙТРАЛІ = {
 "тепла":      dict(нейтраль_дуга=дуга_температури("тепла"), метал="золото",
    приклади="кемел, беж, теплий сірий, олива, вершковий/off-white",
    акцент_нахил="теплий бік тону (жовто-червоний)", уникати="справжній холодний білий"),
 "холодна":    dict(нейтраль_дуга=дуга_температури("холодна"), метал="срібло",
    приклади="нейві, холодний сірий, справжній білий, чорний",
    акцент_нахил="холодний бік тону (синій)", уникати="жовтувато-теплий беж"),
 "нейтральна": dict(нейтраль_дуга=None,        метал="обидва",
    приклади="і теплі, і холодні нейтралі", акцент_нахил="без нахилу", уникати="—"),
 # МЕТАЛ ОЛИВИ — ДЕФОЛТ, А НЕ ПЕРЕЛІК (Н-V04-012). Тут стояв рядок «золото
 # (частіше), але буває холодна олива -> срібло»: на питання людини «золото
 # чи срібло?» реєстр відповідав реченням про те, що буває по-різному, і це
 # речення їхало в `bridge._основи` (bridge.py:414) як фолбек вибору. Лишаємо
 # «золото» дефолтом БЕЗ елісітації; з елісітацією його перекриває бік,
 # обраний людиною (див. `температура`, блок під `рек = ТЕМП_НЕЙТРАЛІ[клас]`).
 # Олива — теплий бік тієї самої осі («оливкові й теплі нейтралі», метал за замовчуванням — золото); своєї дуги
 # тону вона не має: доти (50, 110) — третя межа, якої не було ні у вікнах `реєстр_правил`, ні в `колір_тон`.
 "оливкова":   dict(нейтраль_дуга=дуга_температури("тепла"), метал="золото",
    приклади="оливкові й теплі нейтралі; при холодній оливі — приглушені холодні",
    акцент_нахил="приглушено (олива = синьо-жовте перетягування, не чисто тепле)",
    уникати="справжній холодний білий (сіріє); чистий яскравий (мутніє)"),
}
# R-CHEV-08 — дубль `palette.температура`: `intent` як параметр мети замість сезону.
def температура(F, source=ДЖЕРЕЛО_ФОТО_ТИПОВЕ, intent=ТИПОВИЙ_НАМІР, самозвіт=None):
    """Будує рекомендацію зі спільного підтвердженого класу, зберігаючи утримання та її вибір."""
    вибір = _ОБ.підтон_палітри(F, source, самозвіт)
    sk = вибір["вимір_підтону"]
    клас = вибір["клас"]
    ел = вибір["елісітація"]
    доступно = вибір["доступно"]
    рек = ТЕМП_НЕЙТРАЛІ.get(клас) or dict(
        нейтраль_дуга=None, метал=None, акцент_нахил=None, приклади=None, уникати=None)
    if клас == "оливкова" and вибір["знак_з_елісітації"]:
        бік = "тепла" if ел["w"] > 0 else "холодна"
        рек = dict(рек, метал=ТЕМП_НЕЙТРАЛІ[бік]["метал"],
                   акцент_нахил=ТЕМП_НЕЙТРАЛІ[бік]["акцент_нахил"])
    сила = sk.get("тепло_сила") if sk["довіра"] >= MIN_TO_EMIT else None
    причина = (None if доступно else
               "підтон не стверджується: нема підтвердженого класу або її відповіді про бік")
    return dict(вимір_підтону=sk, придатно=доступно, клас=клас,
        тепло_сила=сила, сила_підтону=round(abs(сила), 2) if сила is not None else None,
        джерело_класу=вибір["джерело"] if доступно else причина,
        знак_осі_придатний=sk.get("вісь_знак_придатний") is True and sk["довіра"] >= MIN_TO_EMIT,
        елісітація=ел, впорскувати_в_запит=доступно and рек["нейтраль_дуга"] is not None,
        нейтраль_дуга=рек["нейтраль_дуга"], метал=рек["метал"], акцент_нахил=рек["акцент_нахил"],
        приклади_нейтралей=рек["приклади"], уникати=рек["уникати"], причина=причина,
        деградація="без підтвердженого класу температурна дуга вільна; бік — із її відповіді",
        строгість=[dict(назва="вибір-понад-температуру",
            коли="її вибір сильніший за пораду за будь-якого наміру",
            основа="температура — порада, не гейт")],
        вісь_A_сила="не стверджується" if сила is None else "магнітуда зі спільного запису",
        вісь_B_надійність=sk["джерело"],
        ранг="співважлива вісь; намір %s не змінює походження кольору" % intent,
        провенанс="клас і джерело — face_features.підтон_палітри; дуги — бік осі тепла колір_тон.дуга_температури")


# ── РЕЄСТР ВІДПОВІДЕЙ ЕЛІСІТАЦІЇ (Н-palette-2-103) ──────────────────────────
# ЩО БУЛО: три ad-hoc кортежі всередині функції, по одному на канал, з РІЗНИМИ
# наборами відповідей. Дві мовчазні дірки, обидві виміряні:
#   · «не бачу різниці» знав ЛИШЕ канал `нейтралі`. показ.html шле рівно це
#     значення і для `білий` (ДРАП_ПОЛЯ.білий), тож жива відповідь не збігалась
#     ні з чим і просто випадала: людина відповіла на три питання, а рахувалось
#     два — і саме на цьому `len(к)` стоїть уся впевненість.
#   · ключі звірялись дослівно: {'метал':'Золото'} з великої давало w=None,
#     тобто «елісітації не було» (виміряно p7.py).
# ЩО СТАЛО: один реєстр, три канали, ОДНАКОВИЙ набір нейтральних синонімів у
# кожному — асиметрія словників і була дірою, тому симетрія тут інваріант, а не
# охайність. Числа — не виміри, а КОНВЕНЦІЯ елісітації (золото↔тепле,
# срібло↔холодне; вершковий↔тепле, оптичний↔холодне; теплі/холодні нейтралі
# буквально). 0.0 — не «нема відповіді», а УТРИМАННЯ: людина дивилась і різниці
# не побачила. Це факт про неї, і він рахується (див. тепло_з_елісітації).
ЕЛ_НЕЙТРАЛЬНІ = _ОБ.ЕЛ_НЕЙТРАЛЬНІ
ЕЛІСІТАЦІЯ_СЛОВНИК = _ОБ.ЕЛІСІТАЦІЯ_СЛОВНИК

def відповідь_каналу(канал, значення):
    """Розпізнає слово єдиним словником виміру ознак."""
    return _ОБ.відповідь_каналу(канал, значення)

def тепло_з_елісітації(білий=None, метал=None, нейтралі=None):
    """Спільний вимір вибору людини з джерелом і довірою."""
    return _ОБ.елісітація(білий=білий, метал=метал, нейтралі=нейтралі)
