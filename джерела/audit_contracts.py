def апострофи(читання, запис):
    """Той самий ключ у двох написаннях — `зв'язок` і `звязок`. Читання одного з них
    мовчки повертає None, і правило вимикається без жодного сліду. Українська тут
    особливо небезпечна: апостроф ставлять по-різному навіть в одному файлі.

    АЛЕ ДВА НАПИСАННЯ НЕ ЗАВЖДИ ДЕФЕКТ, і перший прогін цього файлу це показав:
      · `м'ятн` / `мятн` у verify — обидва КЛЮЧІ однієї таблиці нормалізації назв
        кольорів. Це навмисна ТОЛЕРАНТНІСТЬ до того, як пише український рітейл, і
        саме так і має бути;
      · `зв'язок` / `звязок` в outfit — обидва ЧИТАЮТЬСЯ через `or`, теж навмисно.
    Дефект — коли написання РОЗІЙШЛИСЬ між роллю або модулем: одне пишуть, інше
    читають; або одне в одному модулі, інше в іншому. Тоді читач мовчки не бачить
    того, що писав писар. Саме це й перевіряється нижче."""
    усі = set(читання) | set(запис)
    норм = collections.defaultdict(set)
    for k in усі: норм[k.replace("'", "").replace("’", "").replace("ʼ", "")].add(k)
    підозрілі = {}
    for база, варіанти in норм.items():
        if len(варіанти) < 2: continue
        ролі = {v: (("чит" if v in читання else "") + ("+пиш" if v in запис else ""))
                for v in варіанти}
        модулі = {v: (читання.get(v, set()) | запис.get(v, set())) for v in варіанти}
        спільні = set.intersection(*модулі.values()) if модулі else set()
        одна_роль = len(set(ролі.values())) == 1
        if спільні and одна_роль:
            continue      # співрозташовані й в одній ролі -> навмисна толерантність
        підозрілі[база] = dict(варіанти=sorted(варіанти), ролі=ролі,
                               модулі={v: sorted(m) for v, m in модулі.items()})
    return підозрілі


# ═══════════ 3. ПРОВЕНАНС: `де=` вказує на функцію, якої нема ═══════════
def провенанс():
    """Кожна константа реєстру несе `де="функція()"` — хто її споживає. Якщо функції
    не існує (перейменували, видалили), провенанс бреше, і це НЕ видно ніяк: реєстр
    читається людиною, не інтерпретатором."""
    биті = []
    for м in МОДУЛІ:
        t = _джерело(м)
        if t is None: continue
        функції = set(re.findall(r'^\s*def\s+([\w\'іїєґА-Яа-я_]+)', t, re.M))
        for m in re.finditer(r'де\s*=\s*"([^"]+)"', t):
            for ім in re.findall(r"([\w'іїєґА-Яа-я_]+)\s*\(", m.group(1)):
                if ім not in функції and not any(ім in (_джерело(x) or "") for x in МОДУЛІ):
                    биті.append((м, m.group(1), ім))
    return биті


# ═══════════ 4. МЕРТВІ ФУНКЦІЇ ═══════════
def мертві_функції():
    """Публічна функція, якої не кличе ніхто — включно зі стендами. Не завжди дефект
    (буває вхід для зовнішнього споживача), але завжди питання: правило, реалізоване
    й не викликане, не міняє жодного рішення."""
    визначені, викликані = {}, set()
    усі_файли = glob.glob("*.py")
    тексти = {f: open(f, encoding="utf-8").read() for f in усі_файли}
    for f, t in тексти.items():
        for m in re.finditer(r'^def\s+([\w\'іїєґА-Яа-я_]+)', t, re.M):
            if not m.group(1).startswith("_"): визначені[m.group(1)] = f
    for f, t in тексти.items():
        for m in re.finditer(r'([\w\'іїєґА-Яа-я_]+)\s*\(', t): викликані.add(m.group(1))
        for m in re.finditer(r'(?:import|from)\s+[\w.]+\s+import\s+([^\n]+)', t):
            for x in m.group(1).split(","):
                части = x.strip().split()
                if части: викликані.add(части[0])
    return {n: f for n, f in визначені.items()
            if n not in викликані and n not in ("прогін", "main")}


