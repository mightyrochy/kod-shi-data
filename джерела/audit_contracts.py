def _корпус():
    """Реєстр правил корпусу. Повертає (коди, звідки).

    ДВІЧІ ВИПРАВЛЕНО, І ДРУГА ПОМИЛКА БУЛА МОЯ. Спершу тут стояв пошук ОДНОГО
    зведеного файла (`корпус-знань.md` / `corpus-registry.md`). Такого файла в
    проєкті нема й не має бути: знання розкладене по темах, і зведений реєстр —
    це не джерело істини, а копія, яка розійдеться. Функція мовчки віддавала
    порожню множину, і розділ 5 звітував КОЖНЕ цитоване правило як незареєстроване
    — 103 «розриви», які насправді були просто кількістю різних кодів у коді.
    Потім я запропонував «покласти зведений файл у проєкт» — тобто лікувати
    відсутність джерела заведенням копії. Це було б новим двійником, а не
    виправленням.

    Правильне джерело — самі файли тем, і воно вже так читається в
    `gate_reach.з_корпусу`. Тут та сама операція, з тим самим шаблоном ID.

    ДВІЙНИКА БІЛЬШЕ НЕМА (07.09.2026). Обидва читачі тепер стоять на `корпус.py`
    — модулі без жодного імпорту з системи, тому цикл, через який двійник
    тримався, не виникає. Розділ 0 лишається на місці: він звіряє вже не дві
    реалізації, а два ВИКЛИКИ, і це досі має сенс — розійтися вони можуть
    аргументом теки."""
    # ТРЕТЯ ПОМИЛКА, ЗНАЙДЕНА 06.09.2026: «файли тем» означало «всі .md у теці».
    # Сім із двадцяти — передачі, файл правок, матриця домен-корпус, карта домену:
    # документи ПРО систему. Реєстр із них — уже не корпус: правило, вигадане в
    # коді й раз назване в передачі, проходило розділ 5 мовчки, і `⚠ ПОЗА
    # КОРПУСОМ` до стилістки не доходило. Той самий аргумент уже стоїть у
    # `gate_reach.МЕТА_ФАЙЛИ` для .py — просто не був застосований до .md.
    # Тепер корпус = файли з префіксом теми; пропущені друкуються, а їхні згадки
    # повертаються окремо: розділ 5 має їх РОЗРІЗНЯТИ, а не мовчати про них.
    тека = КР.тека()
    if not тека:
        return set(), None, {}, None, []
    теми, інші = КР.файли(тека)
    коди = КР.ід(тека)
    мета = {}
    for f in інші:
        with open(os.path.join(тека, f), encoding="utf-8", errors="replace") as fh:
            мета[f] = set(КР.ID_ПРАВИЛА.findall(fh.read()))
    return коди, "%d файлів тем у %s (пропущено %d документів про систему)" % (
        len(теми), тека, len(мета)), мета, тека, теми

