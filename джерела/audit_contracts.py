    # «тема називає → значить, ⚠ ПОЗА КОРПУСОМ хибне». Ручна перевірка всіх п'яти
    # спрацювань показала протилежне: у темах 10/11 це ПЕРЕХРЕСНІ ПОСИЛАННЯ
    # («корпус уже має R-HELM-03», «(`near`, K-CLR-04)»), а не визначення — записи
