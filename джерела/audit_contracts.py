    # знають, але воно згадане в документі про систему. Це не «нема ніде» (перший
    # список) і не «є в темі»: це правило, чий єдиний слід — наша власна передача.
    # Окремо, бо й лікується інакше — внести в тему або в `ПОЗА_КОРПУСОМ`.
    лише_мета = sorted(
        (c, sorted(f for f, s in _МЕТА_ЗГАДКИ.items() if c in s))
        for c in цитовані
        if c not in _РЕЄСТР_КОРПУСУ and c not in O.ПОЗА_КОРПУСОМ
        and any(c in s for s in _МЕТА_ЗГАДКИ.values()))
    # ДЗЕРКАЛЬНИЙ БІК, ЯКОГО НІХТО НЕ МІРЯВ: ID сидить у `ПОЗА_КОРПУСОМ`, хоч тема
    # його вже називає, — і знахідка виходить стилістці з хибним «⚠ ПОЗА КОРПУСОМ».
    # Словник переписували 24.08 саме через цей дефект; теми 10/11 додано ПІСЛЯ
