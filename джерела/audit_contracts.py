_БЛОК_ДЕКЛАРАЦІЇ = re.compile(r'ЗОВНІШНІ_ВХОДИ\s*=\s*\{.*?\n\}', re.S)


def _без_коментарів(текст):
    """Джерело без `#`-коментарів. Токенайзером, а не регуляркою: `#` усередині
    рядкового літерала — не коментар, і регулярка на цьому ламається."""
    import io, tokenize
    try:
        куски = []
        for tok in tokenize.generate_tokens(io.StringIO(текст).readline):
            if tok.type == tokenize.COMMENT:
                continue
            куски.append(tok)
        return tokenize.untokenize(куски)
    except (tokenize.TokenError, IndentationError, SyntaxError):
        # не мовчати: краще просканувати з коментарями, ніж пропустити модуль
        return текст


