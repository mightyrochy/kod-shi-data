def оцінка(вхід):
    """Один крок «Оціни мій образ» — див. шапку модуля."""
    d = _json.loads(вхід) if isinstance(вхід, str) else (вхід or {})
    дамп = lambda x: _json.dumps(x, ensure_ascii=False, default=str)
    крок = d.get("крок")
    почато = _time.time()
    if крок == "речі_промпт":
        return дамп(dict(промпт=_О.промпт_речей(d.get("фото")), підписи=_РФ.підписи_фото(d.get("фото"))))
    if крок == "речі":
        return дамп(_О.речі_з_відповіді(d.get("відповідь_моделі"), d.get("фото")))
    if крок == "перелік":
        шкіра = None
        if d.get("пікселі"):        # вікно її дотику міряється без її шкіри, як у `суд`
            шкіра = (_О.профіль(d)[0].get("шкіра") or {}).get("hex")
        return дамп(dict(hex=_О.перелік(d.get("речі"), d.get("пікселі"), шкіра), довідник=_О.довідник_виправлень(),
                         для_слів=_О.речі_для_слів(d.get("речі"))))
    if крок == "виправити":
        р = _О.виправити_речі(d.get("речі"), d.get("дії"), d.get("лічильник"))
        return дамп(dict(р, для_слів=_О.речі_для_слів(р["речі"])))
    if крок == "каталог":
        р = _О.прогріти_каталог(d)
        return дамп(dict(р, мс=round((_time.time() - почато) * 1000)))
    if крок == "суд":
        р = _О.суд(d)
        return дамп(dict(р, мс=round((_time.time() - почато) * 1000)))
    if крок == "оцінка_промпт":
        return дамп(dict(промпт=_О.промпт_оцінки(d.get("суд") or {}, d.get("питання"),
                                                 мова_тексту=d.get("мова_тексту"))))
    if крок == "допит_промпт":
        return дамп(dict(промпт=_О.промпт_допиту(d.get("суд") or {}, d.get("питання"),
                                                 d.get("попередня"), мова_тексту=d.get("мова_тексту"),
                                                 питання_оцінки=d.get("питання_оцінки"))))
    if крок == "допит":
        return дамп(_О.прийняти_допит(d.get("відповідь_моделі")))
    if крок == "оцінка":
        р = _О.прийняти_оцінку(d.get("відповідь_моделі"), d.get("суд") or {})
        # повтор один: вердикт проти суду і картка без «що вдало», яке суд підтримує, — одним рядком
        р["повтор"] = " ".join(х for х in (_О.повтор_вердикту(d.get("суд") or {}, р.get("сторож")),
                                           _О.повтор_вдалого(d.get("суд") or {}, р.get("картка"))) if х) or None
        return дамп(р)
    return дамп(dict(помилка="невідомий крок оцінки «%s»" % крок))


async def оцінка_а(вхід):
    """`оцінка` для показу в Pyodide: кроки «суд» і «каталог» ідуть з поступками головному потоку сторінки (
    дотик «Так, оцінюй» чекав кінця суду; екран «Роздивляюсь речі…» не відповідав, поки піднімався
    каталог), решта кроків — як `оцінка`. Відповідь та сама; `мс` — стінний час разом із поступками."""
    d = _json.loads(вхід) if isinstance(вхід, str) else (вхід or {})
    if d.get("крок") not in ("суд", "каталог"):
        return оцінка(d)
    почато = _time.time()
    р = await (_О.суд_без_блоку(d) if d["крок"] == "суд" else _О.прогріти_каталог_без_блоку(d))
    return _json.dumps(dict(р, мс=round((_time.time() - почато) * 1000)), ensure_ascii=False, default=str)

