def оцінка(вхід):
    """Один крок «Оціни мій образ» — див. шапку модуля."""
    d = _json.loads(вхід) if isinstance(вхід, str) else (вхід or {})
    дамп = lambda x: _json.dumps(x, ensure_ascii=False, default=str)
    крок = d.get("крок")
    почато = _time.time()
    if крок == "речі_промпт":
        return дамп(dict(промпт=_О.промпт_речей(d.get("фото"))))
    if крок == "речі":
        return дамп(_О.речі_з_відповіді(d.get("відповідь_моделі"), d.get("фото")))
    if крок == "каталог":
        р = _О.прогріти_каталог(d)
        return дамп(dict(р, мс=round((_time.time() - почато) * 1000)))
    if крок == "суд":
        р = _О.суд(d)
        return дамп(dict(р, мс=round((_time.time() - почато) * 1000)))
    if крок == "оцінка_промпт":
        return дамп(dict(промпт=_О.промпт_оцінки(d.get("суд") or {}, d.get("питання"),
                                                 мова_тексту=d.get("мова_тексту"))))
    if крок == "допит_промпт":
        return дамп(dict(промпт=_О.промпт_допиту(d.get("суд") or {}, d.get("питання"),
                                                 d.get("попередня"), мова_тексту=d.get("мова_тексту"))))
    if крок == "допит":
        return дамп(_О.прийняти_допит(d.get("відповідь_моделі")))
    if крок == "оцінка":
        р = _О.прийняти_оцінку(d.get("відповідь_моделі"), d.get("суд") or {})
        р["повтор"] = _О.повтор_вердикту(d.get("суд") or {}, р.get("сторож"))
        return дамп(р)
    return дамп(dict(помилка="невідомий крок оцінки «%s»" % крок))
