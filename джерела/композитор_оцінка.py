def _оцінити(F, комбо, тіло, жорстке_ні, вето, самозвіт=None, **kw):
    """Повна перевірка комбінації. (блокує, сума_сил, знахідки).

    `самозвіт` стоїть ІМЕНОВАНИМ, а не в `**kw`, навмисно: `kw` цілим їде в
    `pipeline.перевірити_образ`, а там це поле не читає ніхто. Тут воно потрібне
    рівно одному споживачеві — `palettes.осі` під K-PAL-16 (Н-V04-011).
    """
    вих = pipeline.перевірити_образ(F, list(комбо), тіло=тіло,
                                   жорстке_ні=жорстке_ні, вето_покриття=вето, **kw)
    зн = []
    # ЗНАЙДЕНО 24.08.2026 (measure_material.py, K-MAT-03): `перевірити_образ` віддає
    # `стани` вже у форматі `для_стиліста` — {стан: [рядки]}, СПИСОК на стан. Цей цикл
    # чекав словника з ключем `знахідки`, тож `isinstance(ст, dict)` був False ЗАВЖДИ,
    # і ЖОДНА знахідка review-шару (колір, погода, формальність, матеріали, нагода)
    # не входила в ключ сортування композитора. Ключ рахувався лише з посадки,
    # композиції, K-INT-04, K-COMP-04, K-PAL-16 і координації. Виміряно на ager,
    # +26 °C: сума сил однакова (3.84) для флісових і нефлісових штанів, хоч review
    # на тих самих речах давав K-MAT-03 1.0 і K-WEA-01 0.5. Той самий рід дефекту,
    # що й `тип=` в елементах: правило не хибне, а недосяжне на межі.
    for ст in (вих.get("стани") or {}).values():
        рядки = ст.get("знахідки") if isinstance(ст, dict) else ст
        зн += list(рядки or [])
    зн += list((вих.get("посадка") or {}).get("знахідки") or [])
    к = вих.get("композиція") or {}
    for ключ in ("жорстке_ні", "вето_покриття", "підлога_інтересу",
                 "тканина_проти_крою", "масштаби"):
        зн += list(к.get(ключ) or [])
    # ── ГІЛКИ ТЕМ 10 І 11 НЕ ВХОДИЛИ В КЛЮЧ СОРТУВАННЯ ВЗАГАЛІ ────────────────
    # ЩО ЦЕ МІНЯЄ (правило 3, виміряно на ager 26.08.2026). `перевірити_образ`
    # віддає гілки ОКРЕМИМИ ключами (`аксесуари`, `верхній_шар`), і цей цикл їх
    # не читав: у ключі сортування було 7 знахідок при +18 і 9 при −5, і з них
    # K-OUT — ЖОДНОЇ, хоч гілка віддавала 4 і 6 відповідно. Тобто обидві теми
    # міняли ПОЯСНЕННЯ й не міняли ВИБІР — рівно та смерть за третім ярусом, яку
    # корпус ловить у чужому коді («правило лишає слід, але не міняє рішення»).
    # Це той самий рід дефекту, що вже ловився тут 24.08.2026 із форматом `стани`.
    #
    # ЩО САМЕ ВХОДИТЬ І ЧОМУ НЕ ВСЕ:
    #   ворота       — так: вони й мають відкидати комбінацію (блокує=True);
    #   преференції  — так: це впорядкування, для нього ключ і існує;
    #   ремонти й команди — НІ. Ремонт — це порада («розстебніть», «вузол ззаду»),
    #     і зарахувати його в СУМУ ШТРАФІВ означало б покарати річ за те, що в неї
    #     є вихід. Комбінація з доступним ремонтом мусить ранжуватись не гірше за
    #     ту, у якої ремонту нема;
    #   питання й без_входу — НІ: сила 0.0, а головне — брак ВХОДУ не є вадою РЕЧІ.
    for гілка, ключі in (("аксесуари", ("ворота", "преференції")),
                         ("верхній_шар", ("ворота", "преференції"))):
        г = вих.get(гілка) or {}
        for ключ in ключі:
            зн += [z for z in (г.get(ключ) or []) if z.get("сила") != "питання"]
    блокує = [z for z in зн if z.get("блокує")]
    # ── K-P0-01 (тема-4 XI.2): ПОСАДКА — ГЕЙТ, НЕ КРИТЕРІЙ З ВАГОЮ ─────────────
    # Блок із шару посадки стоїть ПЕРЕД будь-яким композиційним ранжуванням: комбінація
    # з блоком посадки ніколи не обходить комбінацію без нього, і між двома блокованими
    # блок посадки важить першим (ключ сортування нижче). Howlett 2013: посадка читається
    # за ≤5 с без обличчя. Слід пишеться лише коли гейт справді спрацював.
    блок_посадки = [z for z in ((вих.get("посадка") or {}).get("знахідки") or []) if z.get("блокує")]
    # П.14 (СТАНДАРТ §4): `trace.запис` — дописування в список модуля, воно не
    # кидає ні на яких даних; єдиний виняток, який тут був можливий, — TypeError
    # від власної зламаної сигнатури виклику, тобто рівно той баг, задля якого
    # слід і пишеться. Ковтати його означало б лишити правило без сліду мовчки.
    if блок_посадки:
        import trace as _СЛ
        _СЛ.запис("K-P0-01", "посадка блокує до композиції", "composer._оцінити",
                  значення="; ".join(str(z.get("суть", ""))[:40] for z in блок_посадки[:2]),
                  сила=1.0, напрям="гейт перед ранжуванням")
    else:
        # ── ПОРОЖНІЙ ГЕЙТ — ТЕЖ ВІДПОВІДЬ, І ВОНА МУСИТЬ БУТИ ВИДНОЮ ──────────
        # ЩО ЦЕ МІНЯЄ (правило 3, друге проходження гейта досяжності). Рядок вище
        # каже «слід пишеться лише коли гейт справді спрацював» — і наслідок був
        # той, проти якого написане K-IO-04: мовчання «гейт порожній» стало
        # невідрізненним від мовчання «ключ ранжування не викликався». Гейт
        # досяжності чесно звітував K-P0-01 мертвим, хоч порядок працює.
        # ВИМІРЯНО (`проби/cmp_K-P0-01.py`): правил шару посадки 10, блокують на
        # найвищій силі 0 — гейт порожній ЗА РІШЕННЯМ КОРПУСУ (K-FIT-01 тема-1:704
        # прямо забороняє підвищувати його до жорсткого гейта «on this evidence»,
        # решта стоїть реплікою під стелею тіру T3), а на живому каталозі блокерів
        # 0 ще й тому, що `верх_см`/`низ_см` беруть із дефолту слота.
        # Тобто мовчання тут ПРАВИЛЬНЕ, і саме тому його треба вимовити: інакше
        # правильна відповідь і зламаний виклик виглядають однаково.
        # П.14: та сама причина, що в гілці вище.
        import trace as _СЛ
        _СЛ.запис("K-P0-01", "гейт посадки порожній — порядок лишається, блоку нема",
                  "composer._оцінити", значення="блокерів посадки 0",
                  сила=None, напрям="гейт перед ранжуванням")
    вих["_блок_посадки"] = len(блок_посадки)
    # ── ПІДЛОГА ІНТЕРЕСУ ДІЯЛА ЛИШЕ ОБОРОННО ─────────────────────────────────
    # ЗНАЙДЕНО ПЕРШИМ ЖЕ ПРОГОНОМ КОМПОЗИТОРА: зібраний образ вийшов з «джерела
    # інтересу: []» — жодного. K-INT-04 при цьому мовчав, бо він реалізований як
    # ЗАБОРОНА ВИДАЛЯТИ останнє джерело (`крок_редагування`), а не як вимога, щоб
    # джерело взагалі БУЛО. Тобто підлога тримала образ, який уже мав акцент, і
    # нічого не казала про образ, зібраний без жодного.
    # Асиметрія неочевидна, поки збиранням займається людина: вона акцент кладе. У
    # композитора такої звички нема, і він законно збирав три нейтралі.
    # Тут — та сама підлога, застосована ПРОАКТИВНО, на етапі вибору.
    # ── K-PAL-16 (Kettlewell): контекст втягує/виштовхує межовий колір (не блокує) ──
    # ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026). Речення K-PAL-16 на ЦЬОМУ
    # шляху не складається — воно приходить готовим у `z["суть"]` з
    # `palettes.контекст_втягує`, і полагоджене сьогодні там. Зміряно тут, на
    # `composer._оцінити` з двома синтетичними образами (межова річ + двоє
    # компаньйонів), рядком у форматі промпта (`bridge._стислі_знахідки`):
    #   before (тепла людина, теплі компаньйони):
    #     · контекст втягує межовий колір у палітру [0.25]
    #   before (холодна людина, холодні компаньйони):
    #     · контекст втягує межовий колір у палітру [0.25]
    #   after  (тепла людина, теплі компаньйони):
    #     · «верх»: колір ледь у палітрі — його тримають теплі компаньйони:
    #       не міняти їх на холодні [0.25]
    #   after  (холодна людина, холодні компаньйони):
    #     · «верх»: колір ледь у палітрі — його тримають холодні компаньйони:
    #       не міняти їх на теплі [0.25]
    # Старий рядок був ДОСЛІВНО однаковий на двох протилежних людях: «контекст» не
    # називає ні річ, ні бік, ні куди вести компанію, а `речі` знахідки в промпт не
    # друкуються — до ші доїжджали лише `суть` і число.
    # ЧОМУ РЕЧЕННЯ НЕ ПЕРЕПИСУЄТЬСЯ ТУТ — І ЧОМУ НЕ ЧЕРЕЗ БРАК ВХОДУ (звірено
    # ревізією 08.09.2026; попередня редакція цього блоку казала, що «бік людини у це
    # місце не приходить», і це НЕПРАВДА). Бік приходить: `_ос` рядком нижче — та сама
    # вісь, знак `_ос["позиція"]["hue"]` і Є `бік`, а `z["чому"]` уже несе «той самий /
    # протилежний бік людини»; поле `ламається` нижче цей бік навіть називає.
    # Скласти речення тут МОЖНА — і саме тому не можна: воно стало б ДРУГИМ емітентом
    # того самого правила поруч із живим у `palettes.контекст_втягує`, і два тексти
    # K-PAL-16 розійшлися б на першій же правці одного з них. Той самий висновок
    # записаний двома рядками нижче про K-INT-04: «один емітент, не два».
    # П.14 (СТАНДАРТ §4): `except Exception … pass` над УСІМ прийомом K-PAL-16
    # означав, що знахідка «компаньйони виштовхують межовий колір» зникала б із
    # вердикту мовчки — а саме її відсутність аудит тричі приписував іншим
    # причинам (утримана вісь тону, самозвіт до судді). Вхід тут свій:
    # риси (`F`), самозвіт і зібрана комбінація.
    import palettes as _PL
    _ос = _PL.осі(F, kw.get("source", "uncontrolled"), самозвіт)
    for z in _PL.контекст_втягує(_ос, list(комбо)):
        # ── ЗНАК — ЦЕ НАПРЯМ, А НЕ ВАГА (17.09.2026) ─────────────────────
        # `контекст_втягує` віддає ПІДПИСАНУ силу: «+» — компаньйони ТРИМАЮТЬ
        # межовий колір у палітрі, «−» — виштовхують. Тут це число йшло
        # просто у `сила_нп`, і виходило двоє неправди заразом.
        #   · Негативна вага гине у вердикті: `_під_підлогою(−0.083)` істинна,
        #     `обмежити_вагу` мітить знахідку підпідлоговою, і `review` її
        #     викидає. Тобто ПОГАНИЙ випадок — єдиний, про який варто сказати, —
        #     до моделі не доїжджав НІКОЛИ. Це третя (і остання) причина, з
        #     якої аудит тримав K-PAL-16 у «без сліду», поряд із утриманою віссю
        #     тону й самозвітом, що не доходив до судді.
        #   · Позитивна вага додавалась у `сума` — ключ ранжування штрафів.
        #     Тобто образ, у якому компаньйони ТРИМАЮТЬ межовий колір (те, що
        #     прийом схвалює), діставав +0.5 штрафу за власну правильність.
        # Тепер у вердикт іде лише випадок «виштовхують», вагою |сила|; напрям
        # лишається в тексті `суть`, який його й називає словами. Схвального
        # каналу в сумі штрафів нема за побудовою, і вигадувати його тут —
        # не місце: «не міняй компаньйонів» — це порада, а не вада образу.
        if (z.get("сила_нп") or 0.0) >= 0:
            continue
        зн.append(dict(_РЕЄСТР._зн("K-PAL-16", "hint", z["суть"],
                                   [комбо[z["річ"]].get("назва") or комбо[z["річ"]].get("id")],
                                   z["чому"], ремонт=[], ламається="межова частка 0.20 і ваги — T3; бік людини з фото на uncontrolled утримано",
                                   поріг=_PL._МЕЖОВА_ЧАСТКА, вимір=float(комбо[z["річ"]].get("_частка_вікна") or 0.0), повна=1.0),
                       сила_нп=abs(z["сила_нп"])))
    # K-INT-04 проактивно тепер у pipeline.перевірити_образ (24.08.2026) і приходить
    # сюди через композиція["підлога_інтересу"] — один емітент, не два.
    # ── K-COMP-04: РОЗРИВ ІНТЕНСИВНОСТІ ВСЕРЕДИНІ КОМБІНАЦІЇ ──────────────────
    # Не потребує пулу — це властивість самої комбінації, тому рахується тут, а
    # K-COMP-01 (ранг у пулі) — поверхом вище, у `зібрати`.
    зн += КО.інтенсивність(O.елементи(list(комбо)))
    # ── ОГОЛОШЕНА СИЛА СТАЄ СТЕЛЕЮ ВАГИ (07.09.2026) ──────────────────────────
    # Це єдине місце, де сходяться знахідки ВСІХ модулів (outfit, fit, silhouette,
    # accessory, outer, coordination, palettes) перед тим, як стати ключем ранжу.
    # Доти сума брала `сила_нп` як є — а частина модулів рахує це число сама й
    # категорію корпусу не питає. Через це шкала FORCE («hard reject · strong
    # large penalty · default small penalty · hint prior only», тема-4) на вибір
    # речі не впливала: `hint` із великою маржею важив як `hard`.
    # Ставити стелю тут, а не в кожному модулі, — тому що інакше кожен новий
    # емітент знову проходив би повз неї мовчки.
    зн = _РЕЄСТР.обмежити_вагу(зн)
    сума = round(sum((z.get("сила_нп") or 0.0) for z in зн if not z.get("блокує")), 3)
    return блокує, сума, зн, вих


def _координація_з(оцінені, найкраще):
    """Чи координація РОЗРІЗНЯЄ образи — над вибіркою, не над добутком.

    ЩО ЗМІНИЛОСЬ У ПИТАННІ. Доти координація була вагою в цільовій функції коду, і
    питання звучало «чи вона міняє ВЕРШИНУ». Вершини нема: продукт образів не
    впорядковує. Але координація й далі дає знахідки над образом ші, і вони їдуть
    у промпт ремонту — отже питання «чи вона взагалі розводить образи» лишається
    осмисленим. Тут воно й рахується: ключ із нею проти ключа без неї, скільки
    комбінацій змінили ранг.
    """
    if len(оцінені) < 2:
        return dict(вершина_змінилась=False, комбінацій_змінили_ранг=0,
                    чи_розрізняє="вибірка замала для висновку")
    # `набір_кандидатів` — ЧИСЛА близькості пулу, не списки елементів. Перша версія
    # передала сюди елементи, і `розкид_набору` спробував порівняти dict із dict.
    елементи = [O.елементи(x["речі"]) for x in оцінені]
    близькості = [КО.середня_близькість(E) for E in елементи]
    інші = [v for v in близькості if v is not None]
    for x, E, бл in zip(оцінені, елементи, близькості):
        зн = КО.координація(E, набір_кандидатів=інші)
        x["близькість"] = бл
        x["координація"] = round(ВАГА_КООРДИНАЦІЇ * (зн[0]["сила_нп"] or 0.0), 4) \
            if зн and зн[0].get("сила_нп") is not None else 0.0
    без = sorted(range(len(оцінені)), key=lambda i: (оцінені[i]["блокує"], оцінені[i]["сума_сил"], i))
    з = sorted(range(len(оцінені)),
               key=lambda i: (оцінені[i]["блокує"],
                              оцінені[i]["сума_сил"] + оцінені[i]["координація"], i))
    зсув = sum(1 for a, b in zip(без, з) if a != b)
    вершина = без[0] != з[0]
    return dict(
        вершина_змінилась=вершина, комбінацій_змінили_ранг=зсув,
        вага=ВАГА_КООРДИНАЦІЇ,
        близькість_обраного=найкраще.get("близькість"),
        внесок_у_ключ=найкраще.get("координація"),
        # ── ПОЛЕ БУЛО, ЗНАЧЕННЯ НЕ БУЛО (08.09.2026, крок аудиту A7) ────────
        # Тут стояло `діагноз_пулу=None` — тобто поле віддавалось порожнім
        # ЗАВЖДИ. `measure_coordination` його читає (`к["діагноз_пулу"]["чому"]`)
        # і падав TypeError на кожному прогоні; прилад, що міряє, чи координація
        # розрізняє образи, не запускався взагалі.
        # Значення є звідки взяти: `КО.розкид_набору` — та сама функція, якою
        # саме правило вирішує, чи ранг узагалі існує. Вона й відповідає на
        # питання, яке прилад ставив: чи має цей пул колірну варіацію.
        діагноз_пулу=КО.розкид_набору(інші),
        образ_без_координації=[(r.get("слот"), (r.get("назва") or "")[:40])
                               for r in оцінені[без[0]]["речі"]],
        чи_розрізняє=("НІ — жодна комбінація не змінила рангу; правило "
                      "підʼєднане формально" if зсув == 0 else
                      "так: %d із %d комбінацій змінили ранг%s"
                      % (зсув, len(оцінені),
                         ", включно з першою" if вершина else ", але перша та сама")))


def _оцінити_комбінації(комбінації, слоти, F, тіло, жорстке_ні, вето, kw):
    """Перший прохід: кожна комбінація — речі, знахідки, блокери."""
    оцінені, перших_чистих = [], None
    # ВІДСТАНЬ ОГЛЯДУ — З НАГОДИ, ОДИН РАЗ НА ВЕСЬ ПРОХІД (K-COND-04). `kw` тут і
    # є сценарій, тож третього джерела правди для `місце`/`формат`/`нагоди` не
    # заводиться. None (сценарій мовчить) лишає ваги такими, якими вони були.
    _дист = _ДИСТ.з_сценарію(dict(місце=kw.get("місце"), формат=kw.get("формат"),
                                  нагода=kw.get("нагода"))).get("дистанція")
    for комбо in комбінації:
        готові = [_у_річ(r, сл, тіло, _дист) for r, сл in zip(комбо, слоти)]
        # ── ВХІД ПЛОЩІ ЗАКРИВАЄТЬСЯ ТУТ, А НЕ В `_у_річ` (Н-outfit-1-081) ────
        # Пʼять колірних правил (K-COL-01/02/05/06, K-COMP-03) були структурно
        # недосяжні, бо `джерело_площі` не ставив НІХТО: `_у_річ` навмисно його не
        # ставить (вигадана площа гірша за мовчання), і це рішення лишається. Вхід
        # закривається з іншого боку: коли краї речей виміряні, площа РАХУЄТЬСЯ з
        # геометрії тіла, і правила перестають мовчати. Виклик стоїть над ЦІЛИМ
        # образом, бо площа — частка образу, і знаменник у підмножині речей хибний
        # (див. `outfit.площі_з_геометрії`). Поки фід не дає довжин, покриття 0 %,
        # утримання лишається на місці, а міряє його `gate_площі.py`.
        готові, _звіт_площ = O.площі_з_геометрії(готові, тіло)
        блок, сума, зн, вих = _оцінити(F, готові, тіло, жорстке_ні, вето, **kw)
        сер_відст = _середня_відстань(комбо)
        оцінені.append(dict(речі=готові, блокує=len(блок), сума_сил=сума,
                            блок_посадки=вих.get("_блок_посадки", 0),
                            середня_відстань=сер_відст, знахідки=зн, вихід=вих,
                            блокери=[z.get("суть") for z in блок]))
        if not блок and перших_чистих is None: перших_чистих = len(оцінені) - 1
    return оцінені, перших_чистих


def _тиск_корпусу_на_слоти(оцінені, слоти):
    """Середня напруга вузла-слота по оцінених комбінаціях: де корпус тисне найменше,
    там колірний розрив найдешевший (вимір на цьому пулі, не константа)."""
    суми = {с: 0.0 for с in слоти}
    for x in оцінені:
        г = ГР.граф(x["знахідки"], x["речі"])
        for в in г["вузли"]:
            if в["вузол"] in суми: суми[в["вузол"]] += в["напруга"]
    n = max(1, len(оцінені))
    return {с: round(v / n, 3) for с, v in суми.items()}


