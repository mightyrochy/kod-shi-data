def _комбінації_вибіркою(по_слотах, слоти, скільки=200, сід=42):
    """(живі_слоти, комбінації, викинуто) — рівномірна вибірка з добутку.

    Порожні слоти ВИКИДАЮТЬСЯ, і перелік живих повертається разом із комбінаціями
    навмисно: `_оцінити_комбінації` зшиває річ зі слотом через `zip`, і мовчазний
    пропуск порожнього слота зсунув би всі наступні речі на чужий слот — річ
    дістала б чужу геометрію, а знахідки — чужу адресу.

    КОМБІНАЦІЯ З ПОВТОРНИМ id НЕ ОЦІНЮЄТЬСЯ (V02, наряд Н-V02-004, 10.09.2026).
    Двослотова річ стоїть у ядрі ДВОХ слотів за задумом `_кандидати_на_слот`:
    комплект їде копією у «верх» і «низ», кардиган — у «верхній_шар»
    (`_слот_альтернативний=True`, `_слот_первинний` тримає рідний слот). Це
    навмисно — модель мусить бачити річ у кожному слоті, де вона грає. Але
    декартів добуток над такими слотами дає комбінації, де ОДНА річ стоїть
    двічі, а `outfit.перевірити_вхід` законно валить такий образ
    (`ValueError: однакові id речей …`, outfit.py:326: знахідки адресуються по
    імені). Вибірка не має права годувати суд таким образом, тож дублі
    відсіюються тут, а їхнє число повертається назовні третім значенням —
    щоб втрата «200 комбінацій → N» не була мовчазною.
    ЗМІРЯНО (repro2 з ФАЗА2_ЗНАХІДКИ.md, стенд_вх.json × каталог_brief.xml):
      before — сіди 0/1/42/4242 × наміри statement/fashion_forward/editorial,
               усі 12 прогонів `пул_речей=0`, `пул_чому=ValueError…`; шлях
               `вимір=N` падав тим самим і під conventional (repro4).
      after  — усі 12 прогонів `пул_речей>0`, `пул_чому` порожнє.
    ЩО ЦЕ МІНЯЄ У ВИБОРІ, А НЕ ЛИШЕ В ПАДІННІ: тиск корпусу рахується тепер над
    МЕНШИМ числом образів — виміряно на тому ж прогоні (statement, каталог_brief,
    ядро 5 речей на слот): з 200 комбінацій знято 8 (сід 4242), 15–24 (сід 0),
    16 (сід 1), 27 (сід 42). Тобто слот розриву обирається над 173–192 образами
    замість 200, і він може вийти інший, ніж дав би добуток із дублями. Це зміна
    вибору, і вона названа: образи з тією самою річчю двічі не були вибором —
    вони були винятком, бо суд їх усе одно не приймав.
    """
    живі = [с for с in слоти if по_слотах.get(с)]
    if not живі:
        return [], [], 0
    розміри = [len(по_слотах[с]) for с in живі]
    усього = 1
    for n in розміри:
        усього *= n
    if усього <= скільки:
        індекси = range(усього)
    else:
        індекси = sorted(random.Random(сід).sample(range(усього), скільки))
    комбінації, викинуто = [], 0
    for i in індекси:
        комбо, x = [], i
        for с, n in zip(живі, розміри):
            комбо.append(по_слотах[с][x % n])
            x //= n
        ід = [r.get("id") for r in комбо]
        if len(set(ід)) != len(ід):
            викинуто += 1
            continue
        комбінації.append(tuple(комбо))
    return живі, комбінації, викинуто


def _образи_для_виміру(F, по_слотах, тіло, скільки=200, сід=42,
                       жорстке_ні=None, вето=None, **kw):
    """(оцінені образи з пулу, викинуто) — для `вимір=N` і для тиску корпусу.

    Друге значення — скільки комбінацій вибірки знято через повторний id речі
    (див. `_комбінації_вибіркою`); воно їде у вихід виміру, щоб різниця між
    «просили 200» і «оцінено N» не була мовчазною.

    `граф` і `ключ` дописуються тут, бо їх читають споживачі (`_вигляд_виміру`
    рахує вузол напруги, `_портфель` розв'язує ними нічию в полюсі O4), а
    `_оцінити_комбінації` про них не знає.
    """
    живі, комбінації, викинуто = _комбінації_вибіркою(по_слотах, list(по_слотах), скільки, сід)
    if not комбінації:
        return [], викинуто
    оцінені, _ = _оцінити_комбінації(комбінації, живі, F, тіло, жорстке_ні, вето, kw)
    for x in оцінені:
        x["граф"] = ГР.граф(x["знахідки"], x["речі"])
        x["ключ"] = tuple(r.get("id") or "" for r in x["речі"])
    return оцінені, викинуто


