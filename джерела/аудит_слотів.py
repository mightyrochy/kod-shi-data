# -*- coding: utf-8 -*-
"""Аудит слотів каталогу: де ОГОЛОШЕНИЙ слот суперечить типу речі в назві.

Оголошений слот — твердження жниварки (категорія-ім'я слота / param «слот»),
і `feed.слот` дає йому пріоритет над назвою. Це правильно, доки твердження
істинне. Аудит міряє, де воно хибне, і НЕ виправляє мовчки.

ПРИКМЕТНИК ≠ ТИП. «Джинсова кепка» — головний убір, «джинси» — низ. Ключ
«джинс» той самий, а тип різний, тож ключ із прикметниковим суфіксом
одразу після нього (джинс-ов-а, пальт-ов-а, костюм-н-ий, шкір-ян-а)
описує МАТЕРІАЛ або КРІЙ, а не річ. Без цього фільтра аудит звинувачує
магазин у власній сліпоті.
"""
import re, collections, feed
import sys

РОДИНА = {"сережки": "прикраси", "кольє": "прикраси", "намисто": "прикраси",
          "браслет": "прикраси", "каблучка": "прикраси", "брошка": "прикраси",
          "прикраси": "прикраси"}
# ОДНА РЕАЛІЗАЦІЯ НА ВИМІР І НА РІШЕННЯ (23.09.2026, рядок 139). Рівно ця функція
# 23.09 піднялась із аудиту в `фід_слот.предмет_назви` — власник подивився очима й
# сказав виправляти, а не лише звітувати. Тримати тут ДРУГУ копію означало б, що
# наступна правка словника розведе вимір і рішення, і аудит почне «не бачити» того,
# що робить продукт. Імена лишаються: `чистка_каталогу` імпортує `_прикметник`.
_ПРИКМ = feed._ПРИКМЕТНИК


def _прикметник(назва, поз, ключ):
    """Чи ключ у цьому місці — прикметник (матеріал/крій), а не назва речі."""
    хвіст = назва[поз + len(ключ): поз + len(ключ) + 3]
    return bool(_ПРИКМ.match(хвіст))


def тип_із_назви(назва):
    """(слот, ключ, позиція) за НАЙРАНІШИМ іменником-типом у назві."""
    return feed.предмет_назви(назва)


def аудит(offers):
    """[(оголошено, з_назви, ключ, offer)] — лише де назва названа іменником."""
    розбіжні = []
    for o in offers:
        сл = feed.слот(o)
        if сл is None:
            continue
        назва = (o.get("назва") or "").lower()
        r = тип_із_назви(назва)
        if r is None:
            continue
        зн, ключ, _ = r
        if РОДИНА.get(зн, зн) == РОДИНА.get(сл, сл):
            continue
        розбіжні.append((сл, зн, ключ, o))
    return розбіжні


if __name__ == "__main__":
    offers, _ = feed.читати_yml(sys.argv[1] if len(sys.argv) > 1 else feed.каталог_на_диску())
    р = аудит(offers)
    зі_слотом = sum(1 for o in offers if feed.слот(o))
    print("речей зі слотом: %d · розбіжностей: %d (%.1f%%)"
          % (зі_слотом, len(р), 100.0 * len(р) / зі_слотом))
    g = collections.defaultdict(list)
    for сл, зн, k, o in р:
        g[(сл, зн)].append((k, o))
    for кл in sorted(g, key=lambda x: -len(g[x])):
        print("\n=== оголошено «%s», назва каже «%s» — %d ===" % (кл[0], кл[1], len(g[кл])))
        for k, o in g[кл][:5]:
            print("    [%s] %s" % (k, (o["назва"] or "")[:64]))
