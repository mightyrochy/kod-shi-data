    # «до підлоги» (646 низів каталог_повний) — рівень тіла цього не розрізняє.
    # Тестувальниця «Ір» (22.09): світло-молочні палаццо до підлоги ж-06633 на
    # прогулянці з собаками. Тому правило каже «без входу» названим полем — у «код
    # не знає» картки й у пункт A13 аксесуарного чекліста, — а не мовчить і не
    # вигадує поріг довжини, якого корпус не дає.
    if надворі and опади in _НАГОДА.МОКРІ_ОПАДИ:
        _довгі = [e for e in одна_на_річ(E)
                  if e.get("слот") in ("низ", "сукня", "комплект") and e.get("довжина_рівень") == "максі"]
