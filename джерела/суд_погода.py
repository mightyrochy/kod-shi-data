def пальта_пулу(кандидати):
    """Речі пулу, які в образі СТАНУТЬ верхнім шаром, — теплі першими. → [запис пулу].

    Слот пулу «верхній_шар» ширший за каталожний: піджак чи кардиган, чий основний
    слот «верх», стоїть там як двослотовий (`слоти_альт` несе «верхній_шар»), а в
    образі рахується своїм каталожним слотом — верхом (`структура_образу`) — і
    блокера «нема верхнього шару» не закриває. Виміряно на «+5, дощ, побачення»
    (каталог_повний): із 26 речей слота перші дві — піджак і кардиган, пальто третє.
    ПОРЯДОК: спершу мітка «тепло» (`outer.ТЕПЛОВІ_ФУНКЦІЇ`: пальто, пуховик, шуба,
    дублянка, парка), далі решта — і всередині кожного класу порядок пулу, той
    самий, у якому пул бачить стилістка. Клас тепла тут не другий смак, а сама
    потреба пальтової смуги: тренч закриває слот, а холоду не закриває (K-OUT-20)."""
    import outer as _ВШ
    речі = [r for r in ((кандидати or {}).get("верхній_шар") or [])
            if r.get("id") and "верхній_шар" not in (r.get("слоти_альт") or ())]
    # ТИП РЕЧІ ПЕРЕБИВАЄ ТИП ВЕРХНЬОГО: фід ставить `тип_верхнього` «пальто» й
    # трикотажному кардигану («"TEPLO" кардиган-пальто максі», віскоза,
    # ж-04837@25union.com.ua) — теплим першим він ставав би при +5 і дощі. Ті самі
    # два типи пакет називає моделі словами: «блейзер» чи «кардиган» пальта не заміняє.
    тепла = [r for r in речі if r.get("тип") not in ("кардиган", "блейзер")
             and (_ВШ.ТЕПЛОВІ_ФУНКЦІЇ.get(r.get("тип_верхнього") or r.get("тип")) or ("",))[0] == "тепло"]
    return тепла + [r for r in речі if r not in тепла]


def погода(E, темп_c=None, опади=None, вітер=None, сонце=False, стан=None, речі=None,
           шар_ошатності=None):
    """K-WEA-01 (температурна мапа, вето на замшу в дощ) + НОВЕ фізичне правило K-WEA-03.

    `шар_ошатності` — {слот: лічба} з `composer.зібрати` (рядок 119): смуга ошатності
    нагоди, скільки речей у слоті БУЛО, скільки придатних за формальністю, скільки
    знято і якими типами. Те саме правило K-WEA-01 говорить із нього ПИТАННЯМ, коли
    шар попросили, а придатного нема; другого правила для цього не заводиться.

    ЩО ТУТ ВИМІРЯНО, А ЩО КОНВЕНЦІЯ:
      · Темне поглинає більше сонячної радіації — ВИМІРЯНО: чорний бедуїнський халат
        поглинає у 2.5 раза більше за білий (Shkolnik, Taylor, Finch, Borut; Nature 283,
        1980, с. 373–375). Це T1.
      · АЛЕ сумарне тепло, отримане людиною, у тому ж експерименті ОДНАКОВЕ: надлишок
        розсіюється конвекцією в зазорі між тканиною й тілом ще до шкіри. Пізніші
        експерименти дають робочий зазор 10–28 мм, максимум ефекту при 28 мм.
      · Отже народне «світле влітку» НЕ підтверджується як таке. Підтверджується інше:
        темне на сонці — проблема лише при ОБЛЯГАЮЧОМУ крої (cling), бо там немає зазору
        для конвекції. Модератор уже є в корпусі: вісь cling/skim/stand-away (K-MAT-06).
      · Мапа шарів і вето на замшу — корпус (C·hard для вето).

    Погода НЕ вигадується: якщо темп_c не дали, температурні правила мовчать."""
    зн = []
    # ── ГРУБЕ СЛОВО ПАСПОРТА ТУТ БІЛЬШЕ НЕ ЗНАЧИТЬ «СУХО» (19.09.2026, РВ-3 З-2) ──
    # Ворота нижче питають конкретне слово («дощ | мокрий_сніг | злива»), а шов
    # приносив і грубе паспортове «так» (`протокол.ВИПАДОК`), і плиткове «нема».
    # Виміряно пробою `рв3_опади.py`: `опади='так'` давало рівно стільки ж
    # знахідок, скільки `опади='ні'`, — тобто «так, надворі мокро» гасило вето
    # замші. Переклад один на систему і лежить на шві (`сценарій.канон_опади`);
    # суддя кличе його ще раз, бо його зовуть і повз шов (проби, прилади, CLI).
    опади = _НАГОДА.канон_опади(опади, темп_c)
    # СТАН ТЕПЕР ВИРІШУЄ (був мертвим параметром): опади, вітер і сонце діють на
    # людину НАДВОРІ. У стані «у_приміщенні» вони не події, а шум у виході — і
    # K-WEA-02 саме тому й перевіряє образ двічі. Температурна мапа лишається в
    # обох станах: шарів набирають на вихід, а не на кімнату.
    # ── «НАДВОРІ» — ЦЕ НЕ ЗАВЖДИ ІМ'Я СТАНУ (17.09.2026, третя причина K-WEA-03) ──
    # ЩО ТУТ СТОЯЛО: `надворі = (стан != "у_приміщенні")`. Але імена станів дає
    # `outfit.стани(речі)`, і воно віддає ДВА стани лише тоді, коли в образі є
    # верхній шар: два стани — це вісь ВИДИМОСТІ (K-WEA-02: пальто ховає те, що
    # під ним), а не вісь місця. Образ без пальта має рівно один стан, і зветься
    # він «у_приміщенні».
    # НАСЛІДОК, ВИМІРЯНИЙ: усі три погодні події цієї функції — дощ (вето на
    # замшу, `strong`), вітер (летка тканина) і сонце (K-WEA-03) — вимикались на
    # КОЖНОМУ образі без верхнього шару. Для K-WEA-03 це робило правило
    # недосяжним за побудовою, а не за даними: його умова — пряме сонце й спека,
    # тобто рівно та погода, у яку пальта не вдягають. Прапорець сонця міг
    # доїхати (і тепер доїжджає), річ могла бути чорна й приглянута — знахідка не
    # виходила однаково.
    # ЩО ТЕПЕР: коли в образі верхнього шару нема, його ЄДИНИЙ стан читається і як
    # «надворі» теж — бо в цьому образі людина й виходить. Коли верхній шар є,
    # поділ лишається старим: подія погоди судиться в стані «надворі».
    _має_два_стани = any((р.get("слот") if isinstance(р, dict) else None) == "верхній_шар"
                         for р in (речі or [])) or any(
                         e.get("слот") == "верхній_шар" for e in E)
    надворі = (стан != "у_приміщенні") or not _має_два_стани
    # ── K-WEA-01: кількість шарів проти температури ─────────────────────────────
    if темп_c is not None:
        смуга = next((d for lo, hi, d in ТЕМП_МАПА if lo <= темп_c < hi), None)
        if смуга:
            # ── ТЕПЛОВІ ШАРИ РАХУЮТЬСЯ З РЕЧЕЙ, А НЕ З ВИДИМИХ ЕЛЕМЕНТІВ ────
            # ЗНАЙДЕНО ПРОГОНОМ 26.08.2026, НЕ ЧИТАННЯМ. `елементи(речі, стан)` —
            # це шар ВИДИМОСТІ (K-WEA-02): у стані «надворі» верх під застібнутим
            # пальтом ВИКИДАЄТЬСЯ, у стані «у приміщенні» викидається пальто. Отже
            # лічба шарів бачила рівно ОДИН шаровий елемент у кожному стані — і
            # видавала «шарів замало для −5°C» силою 1.0 і образу зі светром під
            # вовняним пальтом, і образу з самим светром. Три конфігурації —
            # однакова знахідка, нуль розрізнювальної здатності.
            # Тепло — не питання видимості: светр під застібнутим пальтом гріє,
            # хоч його ніхто не бачить. Тому лічба йде по РЕЧАХ, коли вони передані,
            # і по елементах, коли ні (стара поведінка, без мовчазної зміни).
            if речі:
                _шарові = [dict(річ=(р.get("назва") or р.get("id")), слот=р["слот"],
                                тепловий_внесок=р.get("тепловий_внесок"))
                           for р in речі if р.get("слот") in ШАРОВІ_СЛОТИ]
            else:
                _шарові = [e for e in одна_на_річ(E) if e["слот"] in ШАРОВІ_СЛОТИ]
            # ── ШАР ≠ ШТУКА (тема-11, K-OUT-20) ─────────────────────────────
            # Тренч дає вітро- і вологозахист і майже нуль теплового; дощовик — нуль.
            # Рахувати їх нарівні з вовняним пальтом означало б сказати «шарів
            # досить» там, де людина мерзнутиме. Внесок ставить `outer`, і коли він
            # не проставлений, штука важить 1.0 — стара поведінка.
            шарів = sum((e.get("тепловий_внесок") if e.get("тепловий_внесок") is not None
                         else 1.0) for e in _шарові)
            _неповні = [e["річ"] for e in _шарові
                        if e.get("тепловий_внесок") is not None and e["тепловий_внесок"] < 1.0]
            треба = смуга["шари"]
            брак = треба - шарів
            if abs(брак) >= 1:
                сила_нп = round(min(1.0, abs(брак) / 2.0), 2)
                бік = "замало" if брак > 0 else "забагато"
                зн.append(dict(_зн("K-WEA-01", "soft" if сила_нп >= C["нп_межа_soft"] else "hint",
                    "шарів %s для %+.0f°C" % (бік, темп_c),
                    [e["річ"] for e in одна_на_річ(E) if e["слот"] in ШАРОВІ_СЛОТИ],
                    "у образі %.2f шар(и) при мапі %.1f для цієї смуги; тканини смуги: %s; %s%s"
                    % (шарів, треба, смуга["тканини"], смуга["нота"],
                       ("; ШАР РАХОВАНО НЕ ШТУКОЮ (K-OUT-20): %s дає вітро- й "
                        "вологозахист, а не тепло" % ", ".join(_неповні)) if _неповні else ""),
                    ремонт="привести кількість шарів до мапи (%s)" % смуга["тканини"],
                    заяви=[_ВМ.заява("layers_off_temperature_map", direction="too_few" if брак > 0 else "too_many",
                                     temperature_c=темп_c, layers=round(шарів, 2), needed=треба,
                                     **({"partial_warmth_items": len(_неповні)} if _неповні else {}))],
                    ремонт_заяви=[_ВМ.заява("layers_to_temperature_map")],
                    ламається="мапа з корпусу, не вимір; вітер, вологість і час надворі "
                              "зсувають відчуття на цілу смугу",
                    поріг=float(треба), вимір=float(шарів)),
                    сила_нп=сила_нп, сила_нп_джерело="вимір (власний: |шари − мапа|)"))
            # ── П-6: У МОРОЗ ПОТРІБНЕ ТЕПЛІШЕ ПАЛЬТО, А НЕ ЧЕТВЕРТА РІЧ ─────
            # ЩО ЦЕ МІНЯЄ. Доти смуга −8…+2 просила 3,5 шару, і «куртка замість
            # пальта в мороз» ловилась ЛІЧБОЮ ШТУК: сукня + светр + куртка давали
            # 2,5 проти 3,5, тобто |брак| = 1 і знахідку «шарів ЗАМАЛО». Діагноз
            # був хибний — бракувало не четвертої речі, а тепла в самому пальті
            # (звіт Research: від смуги 2–10 до −8…2 UTCI просить лише +0,17 clo,
            # тобто ІНШЕ ПАЛЬТО), і ремонт «додати шар» вів рівно не туди. Відколи
            # мапа просить 2,5, той образ лічбою тихий — і цей рядок питає те, чого
            # лічба штук сказати не може: чи цей верхній шар взагалі тепловий.
            # ЧОМУ ТІЛЬКИ «частково», А НЕ «майже ні» / «ні». Про тренч, плащ,
            # дощовик і вітровку в холоді вже говорить K-OUT-20
            # (`верхнє_погода.теплові_знахідки`, нижче +10 °C, сила росте з
            # морозом) — другий рядок про те саме був би двома рядками про одне.
            # Лишається рівно діра: куртка, бомбер, анорак, жилет, кардиган, пончо
            # («частково») — тип обіцяє половину шару, і жодне правило цього в
            # морозі не казало.
            # БЕЗ МІТКИ — МОВЧАННЯ, А НЕ ЗДОГАД: мітку кладе `pipeline` з
            # `верхнє_погода.теплова_функція`; викликач, що подав речі напряму
            # (проба, прилад, CLI), мітки не має, і правило тоді не спрацьовує —
            # той самий принцип, що «погоди не вигадуємо».
