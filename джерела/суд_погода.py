def пальто_це_образ(стани_E, смуга_погоди=None):
    """K-WEA-02 (корпус, C·strong): «у холодний сезон більшість спостерігачів бачать лише
верхній шар → композиція будується ВІД ПАЛЬТА досередини». Досі це жило в коді лише як
механізм двох станів — образ перевірявся окремо надворі й у приміщенні, але ніщо не
казало, що зовнішній стан набагато тихіший за внутрішній. Тобто яскрава сукня під
тьмяним пальтом проходила без жодного слова, хоча її ніхто не побачить."""
    if смуга_погоди is None or смуга_погоди not in _НАГОДА.ПАЛЬТОВІ_СМУГИ:
        return []
    над = стани_E.get("надворі"); вн = стани_E.get("у_приміщенні")
    if not над or not вн:
        return []
    відсутні = бракує(над + вн, ("площа",))
    if відсутні:
        return [_брак_входу("K-WEA-02", відсутні, ("площа",))]
    def інтерес(E):
        """(нижня, верхня) межі інтересу стану — сума (хрома × площа) по його видимих речах."""
        м = [(межі_кольору(e), e["площа"]) for e in E]
        return (sum(x[2] * пл for x, пл in м if x is not None),
                sum(x[3] * пл for x, пл in м if x is not None))
    (н_над, в_над), (н_вн, в_вн) = інтерес(над), інтерес(вн)
    НУЛЬ_ІНТЕРЕСУ = 1e-6   # допуск числа з плаваючою комою: інтерес стану «нуль» — не межа правила стилю
    ПІДЛОГА = 6.0      # T3: приблизно акцентний аксесуар C*60 на 10% видимого поля
    if в_вн <= НУЛЬ_ІНТЕРЕСУ or н_над >= ПІДЛОГА:
        return []
    if н_вн <= НУЛЬ_ІНТЕРЕСУ or в_над >= ПІДЛОГА:
        return [без_входу_кольору("K-WEA-02", [(e,) for e in над + вн if не_вимір(e)],
                                  перевірка="cannot_tell_colour_left_under_coat")]
    i_над, i_вн = в_над, н_вн
    втрата = 1.0 - i_над / ПІДЛОГА
    сила_нп = round(min(1.0, втрата), 2)
    видимі_над = sorted({e["річ"] for e in над})
    return [dict(_зн("K-WEA-02", "soft" if сила_нп >= C["нп_межа_soft"] else "hint",
        "весь колір лишився під пальтом", видимі_над,
        "колірний інтерес надворі %.1f (підлога %.0f), у приміщенні %.1f; при %s "
        "більшість спостерігачів бачить лише верхній шар" % (i_над, ПІДЛОГА, i_вн, смуга_погоди),
        ремонт=["будувати образ ВІД ПАЛЬТА досередини (K-WEA-02), а не навпаки",
                "АБО винести колір у шарф/шапку/сумку — те, що видно поверх пальта"],
        ламається="норма для холодного сезону; якщо людина йде з дверей у двері або пальто "
                  "буде розстібнуте, внутрішній образ видно й правило слабшає",
        поріг=0.0, вимір=round(втрата, 2),
        заяви=[_ВМ.заява("all_colour_under_coat")],
        ремонт_заяви=[_ВМ.заява("build_from_coat_or_colour_on_top")]),
        сила_нп=сила_нп, сила_нп_джерело="вимір (власний: втрата колірного інтересу між станами)")]

