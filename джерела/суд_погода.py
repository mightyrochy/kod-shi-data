    # ── K-WEA-01: вітер і легкі кльоші ─────────────────────────────────────────
    # Було мертвим параметром: «вітер» приймався й нікуди не йшов. Потрібне поле силуету —
    # додане в схему; поки каталог його не дає, правило мовчить (не вигадує силует).
