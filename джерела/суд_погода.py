def смуга_ніг(смуга_погоди):
    """Погоджена смуга ніг для коду погоди, без числового перетворення."""
    return next((d for коди, d in СМУГИ_НІГ if смуга_погоди in коди), None)

def покриття_ноги(речі, смуга_погоди):
    """Наскільки панчішні вкривають ногу. ОДИН СВІДОК із K-HOS-01: смуга den зі
`смуга_ніг(смуга_погоди)`; власного порога тут нема й бути не може."""
    смуга = смуга_ніг(смуга_погоди)
    if смуга is None:
        return None
    колготки = [р for р in (речі or ()) if р.get("слот") == "колготи"]
    if not колготки:
        return None
    den = next((р.get("den") for р in колготки if р.get("den") is not None), None)
    lo, hi = смуга["den"]
    назва = next((к.get("назва") or к.get("id") or "колготки" for к in колготки), "колготки")
    if den is None:
        return dict(покриття=None, den=None, смуга=(lo, hi), назва=назва,
                    поле="den (`feed.панчішні_атрибути`)")
    if lo <= 0:
        return dict(покриття=0.0, den=float(den), смуга=(lo, hi), назва=назва, поле=None)
    return dict(покриття=min(1.0, float(den) / float(lo)), den=float(den),
                смуга=(lo, hi), назва=назва, поле=None)

