    # ── K-WEA-01: ПОДІЛ У ДОЩ — ПРАВИЛО Є, ВХОДУ НЕМА (24.09.2026, рядок 161) ──
    # Корпус (тема-4 IX.4): «Rain and wind constrain fabric, HEM and footwear
