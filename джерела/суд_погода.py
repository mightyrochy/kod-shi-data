# 10–18 °C мапа просить ДВА шари, і другим буває кардиган чи жакет поверх верху
# (K-WEA-01 рахує його шаром торса): обов'язковий верхній шар дав би там третій, і
# сам K-WEA-01 сказав би «шарів забагато». Там лишається лічба шарів, як доти.
def пальтова_смуга(темп_c):
    """Смуга `ТЕМП_МАПА`, у якій верхній шар — обов'язковий слот повноти, або None.

    None — і коли температуру не дали: погода тут не вигадується (так само мовчать
    температурні правила `погода`). П.14: ловиться рівно те, що дає нечислове поле
    сценарію (порожня плитка, слово замість числа), — `float` кидає на ньому
    TypeError або ValueError, і це «температуру не дали», а не поломка коду."""
    try:
        т = float(темп_c)
    except (TypeError, ValueError):
        return None
    смуга = next((d for lo, hi, d in ТЕМП_МАПА if lo <= т < hi), None)
    return смуга if (смуга and смуга["шари"] > 2) else None


