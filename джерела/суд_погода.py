# МЕЖА — З МАПИ, НЕ З ГОЛОВИ: смуги `ТЕМП_МАПА`, де мапа просить ПОНАД ДВА шари на
# торсі, — 2–10 °C (2.5, «легке пальто»), −8–2 (3.5, «пальто — це образ»), <−8 (4,
# «пух, мембрани»), тобто нижче +10 °C. Та сама межа вже стоїть на K-WEA-02
