                              "і не має права мовчки викинути річ. «незахищена_шкіра» з "
                              "ВОЛОГІ_ВЕТО не має АВТОМАТИЧНОГО писача і не може його "
                              "мати: слово магазину каже «шкіра», а захищена вона чи "
                              "ні — ознака обробки, якої у фіді нема жодним полем. Це "
                              "значення лишається для руки (стиліста), і саме тому "
