            # пулу, а модель, що взяла його свідомо з поясненням, лишає його (п.17). Виняток
            # — названий у «ламається» нижче: утеплювач, оголошений СЛОВОМ (`наповнювач`:
            # пух, синтепон…), — тоді «куртка» може бути пуховиком, і рядок лишається soft.
