# не розходилися після додавання нового наміру.
СМІЛИВІ_НАМІРИ = _РЕЄСТР.сміливі_наміри()


def підпул(пул, k):
    """Перші k речей КОЖНОЇ гілки (ядро / на межі / розрив), а не перші k списку.

    Простий зріз `пул[:k]` був би хибний під сміливим наміром: гілки стоять у
    хвості (ядро + межа + розрив конкатенацією), і зріз лишив би саме ядро —
    тобто намір знову перестав би доходити до вибору, а це вже виправлений
    дефект («пул і переможець ІДЕНТИЧНІ в усіх 6 сценах»).
    """
    з_гілок, лічильник = [], {}
    for r in пул:
        г = r.get("_гілка") or ГІЛКА_ЯДРО
        n = лічильник.get(г, 0)
        if n >= k: continue
        лічильник[г] = n + 1
        з_гілок.append(r)
    return з_гілок


def перемішати(послідовність, сід, мітка):
    """Впорядкувати за ід і перемішати спільною політикою на місці."""
    послідовність[:] = _ПВ.порядок(послідовність, сід, мітка)
    return послідовність
