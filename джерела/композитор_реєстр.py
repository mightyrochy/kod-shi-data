# 6 сценах — намір не доходив до вибору. Тепер під сміливим наміром пул на слот =
#   ядро    — K речей із центру вікон обраної гілки (як було);
#   на межі — K речей із вікон ІНШИХ гілок розвилки цієї людини (звичайні, на межі,
#             під statement — тріада), що НЕ влучають у ядро; кожна несе ім'я схеми;
#   розрив  — у КОЖНОМУ слоті далеко від обличчя, де є з чого ламати (ПУЛ-НАМІР): K речей поза всіма вікнами, найдальші від
#             палітри перші. Далеко від обличчя = near < NEAR_МІН (`колір_річ.
#             SLOT_NEAR_FALLBACK` — правила біля обличчя K-CLR-02/04 там не діють за
#             власним порогом корпусу), не верхній шар (там теплові ворота). Перший за
#             найменшим тиском корпусу — «слот розриву» пакета.
# Скільки речей кожної гілки бачить модель, вирішує не K тут, а частка гілки в квоті
# слота семплера (`семплер.ДОЛЯ_МЕЖІ` / `ДОЛЯ_РОЗРИВУ`, ПУЛ-НАМІР): K — лише запас.
# Композитор сам далі ранжує тим самим ключем — його вершина лишається обережним
# полюсом; ширший пул бачить МОДЕЛЬ, а полюс O5 показує найкращий образ із розривом.
ГІЛКА_ЯДРО, ГІЛКА_МЕЖА, ГІЛКА_РОЗРИВ = "ядро", "на межі", "розрив"

# ── ВІДКЛАДЕНЕ РІШЕННЯ, НЕ ЗАБУТЕ ───────────────────────────────
# Це не документ про систему — це один запис, який тримає рішення, свідомо
