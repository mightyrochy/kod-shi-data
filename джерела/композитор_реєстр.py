K_ГІЛКИ = 20
СЛОТИ_ГРАФА = ГР.СЛОТИ
СІД_ВИБІРКИ = 0            # дефолт, коли сід прогону не подано (CLI, тести)
# ── НАМІР ДОХОДИТЬ ДО ПУЛУ ────────────────────────────────────────
# Виміряно: під conventional / fashion_forward / statement правила міняли ГОЛОС
