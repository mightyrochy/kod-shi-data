K_ПЕРЕБОРУ = 5

# СТЕЛЯ ВЛАСНОГО ПЕРЕБОРУ. `itertools.product` по слотах росте як K^|слоти|: на
# чотирьох слотах це 5⁴ = 625 комбінацій, на шістнадцяти — 5¹⁶ ≈ 152 мільярди, і
