def _вигляд_виміру(F, по_слотах, тіло, слоти, скільки, сід, жорстке_ні, вето, kw):
    """Той самий ВИГЛЯД, що композитор давав до 31.08 — але над ВИБІРКОЮ.

    ЩО ЦЕ І ЧИМ НЕ Є. Тести читали з `зібрати()` не лише `_оцінені`, а й похідні
    від них числа: `перебрано`, `чистих`, `граф` і `вузол_напруги` найкращої
    комбінації, `портфель`. Питання, які вони ставлять, живі — «чи правило хоч раз
    спрацювало на речах із фіду», «чи граф має ребро K-INT-04». Померло лише те,
    що код САМ обирав переможця й показував його моделі.

    Тому вигляд відновлено тут, за прапорцем `вимір=N`, і рахується він над
    вибіркою з `вимір_правил`, а не над декартовим добутком: пам'ять не залежить
    від кількості слотів. `bridge` цього прапорця не передає ніколи.
    """
    оцінені, викинуто_дублів = _образи_для_виміру(
        F, по_слотах, тіло, скільки=скільки, сід=(сід or 42),
        жорстке_ні=жорстке_ні, вето=вето, **kw)
    if not оцінені:
        return dict(_оцінені=[], перебрано=0, чистих=0,
                    вибірка=dict(скільки=0, викинуто_дублів=викинуто_дублів))
    # ── ВИБІРКА ВІДДАЄТЬСЯ ВПОРЯДКОВАНОЮ, А НЕ В ПОРЯДКУ ЖЕРЕБА ──────────────
    # Композитор сортував `_оцінені` за ключем, і тести читають саме ПОРЯДОК:
    # «при +14 тренч вище за пуховик, при −5 — нижче» — це і є розрізнювальна
    # здатність правила. Перша версія виміру віддавала образи в порядку вибірки,
    # тож ранг був жеребом і правило виглядало мертвим. Сортування те саме:
    # спершу без блокерів, далі за сумою сил; id — щоб нічиї не гуляли між
    # прогонами.
    # ── K-P0-01 ПЕРЕЇХАВ ІЗ КОМЕНТАРЯ В КЛЮЧ (17.09.2026) ────────────────────
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ. Блок у `_оцінити` вже носить заголовок «ПОСАДКА —
    # ГЕЙТ, НЕ КРИТЕРІЙ З ВАГОЮ» і дослівно обіцяє: «між двома блокованими блок
    # посадки важить першим (ключ сортування нижче)». Ключ нижче цього не робив:
    # він брав `x["блокує"]` — ЛІЧБУ блокерів будь-якого роду, — тож комбінація з
    # ОДНИМ блоком посадки ставала попереду комбінації з ДВОМА композиційними,
    # тобто «не сидить» вигравало в «сидить, але два зауваження». Це і є
    # «зважений критерій», який правило називає помилкою; посадка важила рівно
    # стільки, скільки будь-яка інша знахідка, і корпусне `strong` на архітектурі
    # жило коментарем. Число `_блок_посадки` рахувалось у `_оцінити` й лежало в
    # кожному рядку `оцінені` — і не читав його НІХТО.
    # after: перший ключ — «посадка блокує?», і лише потім лічба решти блоків та
    # сума сил. Комбінація, яка не сидить, не обходить жодну, яка сидить.
    # МЕЖА, НАЗВАНА ПРЯМО: гейт спрацьовує лише там, де посадку взагалі є з чого
    # порахувати. На живому каталозі `верх_см/низ_см` беруть із ДЕФОЛТУ СЛОТА
    # (фід не несе мірок виробу), і тоді шар посадки нічого не блокує — виміряно
    # на `каталог_повний.xml`: 12 образів, блокерів посадки 0. Тобто правило тепер
    # правильне й мовчазне; оживить його не правка тут, а мірки виробу у фіді.
    оцінені.sort(key=_ключ_ранжування)
    найкраще = оцінені[0]
    г = найкраще["граф"]
    вузол = ГР.вузол_напруги(г)
    _розр_вим, _резон_вим = ГР.розрізнювальні(оцінені)[:2]
    живі = [с for с in слоти if по_слотах.get(с)]
    return dict(
        _оцінені=оцінені,
        перебрано=len(оцінені),
        чистих=sum(1 for x in оцінені if not x["блокує"]),
        самоперетинів=0,
        граф=г, вузол_напруги=вузол,
        образ=[dict(id=r.get("id"), назва=r.get("назва"), слот=r.get("слот"),
                    ціна=r.get("ціна"), тип=r.get("тип"),
                    відстань_до_центру=r.get("_відстань"))
               for r in найкраще["речі"]],
        знахідки=найкраще["знахідки"], блокери=найкраще["блокери"],
        портфель=_портфель(оцінені, найкраще, живі, вузол=вузол),
        вибірка=dict(спосіб="рівномірна вибірка з пулу (вимір_правил), не добуток",
                     скільки=len(оцінені), викинуто_дублів=викинуто_дублів),
        # ОЗНАЧЕННЯ БЕРЕТЬСЯ З `graph`, А НЕ ВИГАДУЄТЬСЯ ТУТ. Перша версія рахувала
        # резонансні як «правило є в УСІХ образах» — і K-CUT-00 випадав, бо
        # спрацьовує не скрізь. Канонічне означення тонше: резонансне те, чия
        # НАПРУГА не різниться між комбінаціями, тобто воно не впорядковує пул.
        резонансні=sorted(_резон_вим), розрізнювальні=sorted(_розр_вим),
        чому_цей=_пояснити(найкраще, оцінені, {}, вузол=вузол, резон=_резон_вим),
        координація=_координація_з(оцінені, найкраще),
        _речі=найкраще["речі"], _вихід=найкраще.get("вихід"))


def зібрати(F, каталог, вікна=None, тіло=None, слоти=None,
            жорстке_ні=None, вето=None, самозвіт=None, **kw):
    """Головний вхід. Повертає образ + ЧОМУ саме він, + що відкинуто й чому.

    Жодного числа «якості образу» не повертає навмисно: R-ABC-08 забороняє числовий
    універсальний style-score, і сума сил знахідок нею б і стала, якби вийшла назовні
    як оцінка. Вона тут — КЛЮЧ СОРТУВАННЯ, і подається саме так."""
    слоти = tuple(слоти or СЛОТИ_БАЗОВІ)
    # ── K-IO-01: ПРОФІЛЬ І СЦЕНАРІЙ — ОБОВʼЯЗКОВІ ВХОДИ (19.09.2026) ──────────
    # Гейт стоїть тут, а не в `bridge.порада` (та навмисно працює до збирання й
    # без пулу) і не в `_поза_сценою` (там «без сцени — нічого не чіпає» — саме
    # це мовчання й закривається). Вихід — та сама форма, що в «порожні слоти»:
    # названий брак, не виняток і не образ під дефолтну смугу. Що таке «сценарію
    # нема» — `сценарій.ВИЗНАЧАЛЬНІ`. Прямі викликачі без нагоди (прилади) тепер
    # дістають `зібрано=False` і `бракує` — це їхній вхід, не дефолт композитора.
    import сценарій as _СЦ
    _брак = None
    if not F:
        _брак = ("профілю нема — образ не збирається: потрібні шкіра, волосся й очі", ["профіль"])
    elif not _СЦ.є_сценарій(kw):
        _брак = (_СЦ.БРАК_СЦЕНАРІЮ, list(_СЦ.ВИЗНАЧАЛЬНІ))
    if _брак:
        return dict(зібрано=False, чому=_брак[0], бракує=_брак[1], правило="K-IO-01",
                    що_робити="назвати нагоду, місце, дрес-код або ошатність — образ "
                              "збирається під подію, а не під невідомий дефолт",
                    відкинуто=[], ноти_слотів={}, слоти_випали=[],
                    кандидатів={с: 0 for с in слоти}, _кандидати={})
    # ── САМОЗВІТ ЇДЕ ВЛАСНИМ КЛЮЧЕМ ДО `_оцінити` (Н-V04-011) ────────────────
    # `kw` тут — поля СЦЕНАРІЮ, і самозвіт у них не приходив ніколи, тож
    # `palettes.осі` під K-PAL-16 судила бік людини утриманою віссю навіть тоді,
    # коли людина відповіла на картки. Кладеться в `kw` рівно тому, що всі три
    # шляхи до `_оцінити` (`_оцінити_комбінації`, `_вигляд_виміру`,
    # `_образи_для_виміру`) передають саме його; іменований параметр `_оцінити`
    # знімає ключ із `kw` і в `pipeline.перевірити_образ` він не потрапляє.
    if самозвіт: kw["самозвіт"] = самозвіт
    # ── ТЕМПЕРАТУРА САМА ПРОСИТЬ ВЕРХНІЙ ШАР ─────────────────────────────────
    # ЗАФІКСОВАНИЙ ДЕФЕКТ (check_edits §28): «K-WEA-01 діагностує брак шару
    # НЕПЕРЕРВНО (+12 → 0.5 · +2 → 0.75 · −10 → 1.0), а композитор НЕ МАЄ ЧИМ ЦЕ
    # ПОЛАГОДИТИ — правило лишає слід, але не міняє рішення». Слот тепер досяжний,
    # але доти його мусив попросити ВИКЛИКАЧ, тобто знати відповідь наперед.
    # Тут температурна мапа корпусу (та сама, що живить K-WEA-01) просить слот
    # САМА: якщо смуга хоче більше ніж один шар на торсі, верхній шар додається.
    # Він НЕОБОВʼЯЗКОВИЙ, тож при нулі SKU випаде з названою причиною — діагноз
    # K-WEA-01 лишиться, але тепер він означатиме «у каталозі нема», а не «ніхто
    # не спитав».
    # ВОРОТА ДВОБІЧНІ (31.08.2026). Доти мапа лише ДОДАВАЛА слот, бо в дефолтних
    # чотирьох його не було, і «зняти» не було чого. Відколи код просить усі слоти
    # каталогу, верхній шар стоїть завжди — і при +26 °C модель діставала пальто
    # в пул. Зміряно: на фіді стенда 13 згадок «верхній_шар» у промпті і в холод,
    # і в спеку. Тепер та сама мапа, що просить шар, його й знімає.
    _нота_шару = None
    _слоти_дефолтні = bool(kw.pop("слоти_дефолтні", False))
    _темп = kw.get("темп_c")
    if _темп is not None:
        import outfit as _O
        _смуга = next((d for lo, hi, d in _O.ТЕМП_МАПА if lo <= _темп < hi), None)
        _хоче = bool(_смуга and _смуга["шари"] > 1)
        if _хоче and "верхній_шар" not in слоти:
            слоти = слоти + ("верхній_шар",)
        # ЯВНИЙ ЗАПИТ ВИКЛИКАЧА СИЛЬНІШИЙ ЗА МАПУ. Перша версія двобічних воріт
        # знімала шар завжди — і зривала слот навіть тоді, коли його попросили
        # руками (CLI, тест «пальто в спеку примусово»). Мапа має право прибирати
        # лише те, що САМА ж і поставила за замовчуванням.
        # ШАР ТРИМАЮТЬ НЕ ЛИШЕ ГРАДУСИ (05.09.2026): дрес-код від 7 (жакет — частина коду),
        # опади/вітер, вулиця нижче +22 °C — верхній шар лишається в слотах; мапа знімає
        # його лише в теплі, у приміщенні, без погоди.
        _о = kw.get("_ошатність"); _lo = None
        if isinstance(_о, (list, tuple)) and len(_о) == 2:
            try: _lo = min(float(_о[0]), float(_о[1]))
            except (TypeError, ValueError): _lo = None
        _тримає = ((_lo is not None and _lo >= 7)
                   or (str(kw.get("дрес_код") or "").lower().replace(" ", "_").replace("-", "_") in ("business_formal", "cocktail", "black_tie", "smart", "formal", "формальний", "вечірній"))
                   or (kw.get("опади") not in (None, "", "ні", 0, False))
                   or ((kw.get("вітер") or 0) and float(kw.get("вітер") or 0) >= 6)
                   or (kw.get("_формат") in ("просто неба", "змішано") and float(_темп) < 22))
        if not _хоче and "верхній_шар" in слоти and _слоти_дефолтні and _тримає:
            _нота_шару = ("верхній шар ЛИШЕНО попри %s °C: %s" % (_темп,
                          "дрес-код" if ((_lo is not None and _lo >= 7) or str(kw.get("дрес_код") or "").lower().replace(" ", "_").replace("-", "_") in ("business_formal", "cocktail", "black_tie", "smart", "formal", "формальний", "вечірній")) else "погода/вулиця"))
        elif not _хоче and "верхній_шар" in слоти and _слоти_дефолтні:
            слоти = tuple(с for с in слоти if с != "верхній_шар")
            _нота_шару = ("слот ЗНЯТО температурою: смуга %s °C просить один шар на торсі, "
                          "тож верхній шар тут зайвий — це не брак каталогу" % _темп)
    # ── НЕОБОВʼЯЗКОВІ СЛОТИ: ПОРОЖНЬО МАЄ ДЕГРАДУВАТИ, А НЕ ВБИВАТИ ЗБІРКУ ────
    # ЗАФІКСОВАНИЙ ДЕФЕКТ (check_edits §28, 26.08.2026): варто було подати
    # «верхній_шар» у слотах — і збірка поверталася `зібрано=False` при 0 SKU,
    # тобто образу не було ВЗАГАЛІ. На обох живих фідах верхнього шару нуль, а
    # влітку його не буде в жодному фіді, отже кожен запит із верхнім шаром давав
    # порожнечу замість образу з названою дірою.
    # ЩО ЦЕ МІНЯЄ: порожній ОБОВʼЯЗКОВИЙ слот (верх/низ/сукня) далі валить збірку —
    # без низу образу справді нема. Порожній НЕОБОВʼЯЗКОВИЙ слот тепер випадає, а
    # діра їде у вихід як `слоти_випали`, і K-WEA-01 має що сказати людині.
    необовʼязкові = tuple(kw.pop("необовʼязкові", None) or СЛОТИ_НЕОБОВЯЗКОВІ)
    # СІД ПРОГОНУ. `pop`, а не `get`: далі kw цілим іде в `pipeline.перевірити_образ`,
    # і зайвий ключ там був би не входом сценарію, а сміттям.
    сід = int(kw.pop("сід", СІД_ВИБІРКИ) or 0)
    # ── ВИМІР: N ОЦІНЕНИХ ОБРАЗІВ ДЛЯ ТЕСТІВ, НЕ ДЛЯ ПРОДУКТУ ────────────────
    # `вимір=N` додає у вихід `_оцінені` — N реальних образів із пулу, кожен уже
    # оцінений. Це НЕ повернення власного перебору: перебір був декартовим
    # добутком по всіх слотах і вбивав процес по пам'яті на шістнадцяти слотах.
    # Тут — вибірка сталого розміру з окремого модуля `вимір_правил`.
    # ПРОДУКТ ЦЬОГО НЕ ПЕРЕДАЄ НІКОЛИ: `bridge` не знає цього параметра, і на це
    # стоїть гейт. Питання «чи правило хоч раз спрацювало на речах із фіду» живе;
    # зникло лише джерело образів, і воно відновлене тут, а не в продуктовому шляху.
    _вимір = int(kw.pop("вимір", 0) or 0)
    речі, відкинуто = _придатні(каталог, жорстке_ні, вето, тіло,
                                 сцен={k: kw.get(k) for k in ("місце", "нагода", "година", "темп_c", "дрес_код", "_ошатність", "intent")})

    по_слотах, ноти = {}, {}
    if _нота_шару:
        ноти["верхній_шар"] = _нота_шару
    for сл in слоти:
        к, нота = _кандидати_на_слот(речі, вікна, сл, тіло, сід,
                                     реєстр_людини=kw.get("реєстр_людини"))
        по_слотах[сл] = к
        if нота: ноти[сл] = нота
    # ── СМІЛИВИЙ НАМІР: гілки «на межі» в кожному слоті й один слот розриву ──────
    намір = kw.get("intent") or "conventional"
    розрив = None
    if намір in СМІЛИВІ_НАМІРИ:
        межа = kw.get("вікна_на_межі")
        if межа is None:
            # вікна межових гілок рахуються на ТІЙ САМІЙ сцені, що й ядро
            # (K-COND-04): інакше ядро судилось би за відстанню, а межа — ні.
            межа = _вікна_на_межі(
                F, слоти, намір, вікна,
                дистанція=_ДИСТ.з_сценарію(dict(місце=kw.get("місце"),
                                                формат=kw.get("формат"),
                                                нагода=kw.get("нагода"))).get("дистанція"))
        усі_вікна = list(вікна or []) + list(межа or [])
        for сл in слоти:
            ядро_ід = {r.get("group_id") or r.get("id") for r in по_слотах[сл]}
            _межові = _кандидати_гілки(речі, межа, сл, ядро_ід, ГІЛКА_МЕЖА, K_ГІЛКИ, сід)
            по_слотах[сл] = по_слотах[сл] + _межові
            # ── ПОРОЖНЯ ГІЛКА МУСИТЬ НАЗВАТИСЬ, А НЕ ЗНИКНУТИ ────────────────
            # ЩО ЦЕ МІНЯЄ (before/after, каталог_повний, statement, сід 42):
            #   before — у слоті «сумка» 248 речей ядра і НУЛЬ «на межі». Ззовні
            #            це невідрізненно від «гілка не рахувалась»: ні ноти, ні
            #            сліду. Саме на цьому місці стояв відкритий червоний.
            #   after  — слот несе рядок із причиною й числом.
            # ЧОМУ ЦЕ НЕ ПОМИЛКА КОДУ, А ФАКТ КАТАЛОГУ. «На межі» = влучає у
            # вікно ІНШОЇ гами цієї людини й НЕ влучає в ядрову. Поки ядровий пул
            # був 5 речей, у гілку падало все, що не втрапило в топ-5, — і вона
            # виглядала населеною завжди. При повному пулі (K_НА_СЛОТ=500) видно
            # справжню картину: кожна сумка, що влучає у вікно межі, влучає й у
            # ядрове, тож окремої межі в цьому слоті просто НЕМА. Ноти тут
            # достатньо: «нема речей» ≠ «річ не потрібна» — той самий принцип,
            # що для слота, який випав.
            if not _межові:
                # ── НОТА НАЗИВАЛА НЕ ТУ ПРИЧИНУ (08.09.2026) ─────────────────
                # ЩО ЗМІРЯНО. `_вікна_на_межі` віддає вікна ІНШИХ гілок розвилки,
                # відкинувши ті, що вже є ядром. Відколи `bridge` будує ядро
                # СОЮЗОМ усіх гілок (01.09.2026, «гілка is None»), відкидається
                # геть усе: на цій людині союз пʼятьох схем дає 251 вікно ядра і
                # РІВНО 0 вікон «на межі»; коли ж гілку обрано («тональна»), ядро
                # має 40 вікон, а межа — 132. Тобто при дефолтному режимі показу
                # гілки «на межі» не існує ЗА ПОБУДОВОЮ, а нота пояснювала це
                # каталогом — і мовчки ховала наслідок правки в іншому модулі.
                # Тут нота розділена на два різні стани, бо в них різний ремонт:
                # порожній перелік вікон лікується вибором гілки, порожній
                # перелік речей — закупівлею джерел.
                _вікна_сл = [q for q in (межа or [])
                             if not q.get("слот") or q.get("слот") == сл]
                _уск = sum(1 for r in речі if r.get("слот") == сл and r.get("lab"))
                _чому = (("гілки «на межі» НЕМА ЗА ПОБУДОВОЮ: ядро зібране союзом "
                          "усіх гілок розвилки, тож вікон «іншої гами» не лишилось "
                          "жодного. Це не властивість каталогу — щоб межа зʼявилась, "
                          "має бути обрана ОДНА схема")
                         if not _вікна_сл else
                         ("гілки «на межі» в цьому слоті НЕМА: жодна з %d речей слота "
                          "не влучає в жодне з %d вікон іншої гами, не влучивши "
                          "водночас у ядрову. Це властивість каталогу, не пропуск — "
                          "сміливий намір тут доходить ядром і розривом"
                          % (_уск, len(_вікна_сл))))
                ноти[сл] = ((ноти.get(сл) + " · ") if ноти.get(сл) else "") + _чому
        # слот розриву: далеко від обличчя, не верхній шар, є з чого ламати — і серед
        # таких той, де КОРПУС НАЙМЕНШЕ ТИСНЕ: середня напруга вузла-слота на
        # ядровому пулі (перший прохід лише над ядром)
        придатні_слоти = {}
        for сл in слоти:
            if сл in ("верх", "сукня", "комплект", "верхній_шар"): continue
            зайняті = {r.get("group_id") or r.get("id") for r in по_слотах[сл]}
            поза = _поза_палітрою(речі, усі_вікна, сл, зайняті, сід)
            if поза: придатні_слоти[сл] = поза
        if придатні_слоти:
            # ── ОСТАННІЙ ДЕКАРТІВ ДОБУТОК, І ВІН ТЕЖ ВИРІЗАНИЙ (31.08.2026) ──
            # ЩО ЦЕ БУЛО. `list(itertools.product(...))` по ВСІХ слотах, щоб
            # порахувати тиск корпусу й обрати слот розриву. Той самий дефект, що
            # й у прибраному переборі переможця, тільки схований у гілці сміливого
            # наміру, тож перше вирізання його не зачепило: шукали за призначенням
            # («перебір коду»), а не за конструкцією.
            # ЗМІРЯНО: до `composer.зібрати` прогін під statement тримає 182 МБ і
            # виконується за 6 с. Далі — OOM-kill без трейсбека, вісім разів у
            # журналі ядра. На 4 слотах добуток давав 5⁴ = 625 кортежів; на 16 —
            # 5¹⁶ ≈ 152 мільярди, і список матеріалізувався ДО того, як вибірка
            # встигала взяти з нього 200.
            # ЩО СТАЛО. Вибірка комбінацій будується одразу, ліниво: пам'ять не
            # залежить від кількості слотів, а тиск корпусу рахується над тим самим
            # числом образів, що й раніше.
            _ядро_пул = {с: [r for r in по_слотах[с] if r.get("_гілка") == ГІЛКА_ЯДРО][:K_ПЕРЕБОРУ]
                         for с in слоти}
            _живі, _комб, _викинуто = _комбінації_вибіркою(_ядро_пул, слоти, скільки=200, сід=(сід or 42))
            ядро_оц, _ = _оцінити_комбінації(_комб, _живі, F, тіло, жорстке_ні, вето, kw)
            тиск = _тиск_корпусу_на_слоти(ядро_оц, слоти)
            сл = min(придатні_слоти, key=lambda с: (тиск.get(с, 0.0), слоти.index(с)))
            поза = придатні_слоти[сл]
            по_слотах[сл] = по_слотах[сл] + поза[:K_ГІЛКИ]
            розрив = dict(слот=сл, речей_поза_палітрою=len(поза), тиск_корпусу=тиск,
                          вибірка_без_дублів=len(_комб), вибірка_викинуто=_викинуто,
                          чому="далеко від обличчя (правила біля обличчя тут не діють за порогом корпусу), не верхній шар "
                               "(теплові ворота); серед таких слотів тут корпус тисне найменше на ядровому пулі (%s); "
                               "поза палітрою є %d речей" % (", ".join("%s %.2f" % (с2, тиск.get(с2, 0.0)) for с2 in sorted(придатні_слоти, key=lambda с2: тиск.get(с2, 0.0))), len(поза)))
        else:
            розрив = dict(слот=None, чому="у жодному придатному слоті нема речей поза палітрою — ламати нічим")
    порожні = [сл for сл, к in по_слотах.items() if not к]
    випали = [сл for сл in порожні if сл in необовʼязкові]
    критичні = [сл for сл in порожні if сл not in необовʼязкові]
    if критичні:
        return dict(зібрано=False,
                    чому="порожні слоти: %s" % ", ".join(критичні),
                    що_робити="розширити вікна або взяти інший каталог; вигадувати "
                              "річ, якої нема, композитор не має права",
                    відкинуто=відкинуто, ноти_слотів=ноти,
                    слоти_випали=випали,
                    кандидатів={с: len(к) for с, к in по_слотах.items()})
    if випали:
        слоти = tuple(с for с in слоти if с not in випали)
        for с in випали:
            ноти[с] = ("слот ВИПАВ: у каталозі нема жодного кандидата. Образ зібрано "
                       "без нього, і це названо, а не сховано — «нема речі» ≠ «річ не "
                       "потрібна»")

    # ── ВЛАСНИЙ ПЕРЕБІР КОДУ ПРИБРАНО (31.08.2026) ───────────────────────────
    # КОД ОБРАЗІВ НЕ ЗБИРАЄ. Він дає кандидатів у слоти; образи складає ші; код
    # СУДИТЬ складене (`pipeline.перевірити_від_моделі`). Власний образ коду не був
    # продуктом і не читався ніде поза самим кодом: ні шаблон артефакта, ні
    # `показ.html` не згадують `образ_коду` жодного разу (зміряно 30.08 і ще раз
    # 31.08). Єдиним його виходом був рядок «ВУЗЬКЕ МІСЦЕ образу, який зібрав код»
    # у промпті — 3 % тексту, порожній у 6 сценах із 8.
    #
    # ЩО ЦЕ ЗВІЛЬНЯЄ. (1) ≈12 с на прогін — 60 % часу збирання йшло на 200 перевірок
    # комбінацій, які нікуди не доїжджали. (2) Пам'ять: `list(itertools.product(...))`
    # росте як K^|слоти|. На чотирьох слотах 5⁴ = 625 кортежів; щойно система
    # почала просити всі слоти каталогу — 5¹⁶ ≈ 152 мільярди, і прогін убивало
    # OOM-kill'ом без трейсбека. Тобто власний перебір був ЄДИНИМ, що не давало
    # віддати моделі повний каталог слотів.
    #
    # РІШЕННЯ УХВАЛЕНЕ 30.08, заблоковане умовою «поки стенд не читає `образи`».
    # Умову знято 31.08 разом із трикроковим циклом; правку не зробив ніхто, і вона
    # два дні жила як запис у передачі, що не міняв коду.
    return dict(
        зібрано=True,
        розрив=розрив,
        відкинуто=відкинуто, ноти_слотів=ноти,
        слоти_випали=випали,
        кандидатів={с: len(к) for с, к in по_слотах.items()},
        # пул кандидатів по слотах — це ВЕСЬ продукт цієї функції: модель компонує
        # з того, що вже пройшло фільтри коду. Полів про власний образ коду тут
        # більше нема — код образів не збирає.
        _кандидати=по_слотах,
        **(_вигляд_виміру(F, по_слотах, тіло, слоти, _вимір, сід, жорстке_ні, вето, kw)
           if _вимір else {}))


# ── ЧОМУ ГІЛКА `вимір=N` ЛИШИЛАСЬ (Н-02-03, С-62, 13.09.2026) ────────────────
# Наряд назвав `_портфель` під `вимір=N` кандидатом на знесення (V31). Правило
# наряду — «є виклик із продукту, тесту чи приладу — лишити», — і вимір каже
# лишити: прапорець передають ДВА прилади, обидва живі й обидва читають саме те,
# що рахує ця гілка:
#   · `measure_coordination.py:62`  — `КМ.зібрати(..., вимір=200)`, далі читає
#     `вершина_змінилась` і `чи_розрізняє` з `_координація_з` (:76–77);
#   · `run_outfit.py:210–212`       — `КМ.зібрати(..., вимір=200)`, далі читає
#     `рез["портфель"]` (:231).
# Мертвий тут не шлях `вимір=N`, а те, про що казав V31: ПРОДУКТ його не передає
# ніколи, тож K-VAR-01 і K-COMP-02 не виносяться на живому шляху. Це інша
# хвороба, і лікує її Т-10 (С-48), а не знесення гілки, якою міряють.

# ── ЧИ ПУЛ ВЗАГАЛІ НЕСЕ ПОЛЮСИ, ЯКІ ПАКЕТ ОБІЦЯЄ (K-VAR-01, 17.09.2026) ─────
# ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after, виміряно на `каталог_повний.xml`,
# `bridge.запити` з `варіантів=6`, сцена «офіс · 18 °C»).
#   before — `pipeline.пакет_для_моделі` називає перші N полюсів зі свого словника
#            БЕЗУМОВНО, не питаючи, чи пул їх витримує. Вимір: пакет оголошував
#            шість полюсів, і серед них «розрив» («одна річ навмисно поза
#            палітрою»), а в пулі з 383 речей на гілці «розрив» стояло РІВНО НУЛЬ —
#            усі 383 були «ядро». Тобто моделі замовляли образ із речі, якої в пулі
#            нема. Виконати таке замовлення можна одним способом: віддати ще одну
#            варіацію тієї самої серединної відповіді — рівно те, що K-VAR-01 зве
#            провалом («a single stereotype per request is a failure»).
#   after  — пакет називає лише ті полюси, які пул СПРОМОЖНИЙ дати, а решту
#            називає вголос окремим рядком вимог: «нема речі» ≠ «полюс не
#            потрібен». Незайняті місця стають ВІЛЬНИМИ задумами, а не мовчазними
#            дублями.
# ЖОДНОЇ НОВОЇ КОНСТАНТИ ТУТ НЕМА, І ЦЕ НАВМИСНО. Кожен предикат стоїть на числі,
# яке вже оголошене зі своїм тіром:
#   · якір         — `виразність_героя` (T3, K-COMP-02), та сама шкала `_виразність`;
#   · колона       — `step_min` (T2, K-COL-01, крок Munsell): колона читається
#                    колоною, поки сусідні світлоти РІЗНЯТЬСЯ МЕНШ ніж на крок;
#   · вузол        — ≥2 кандидати хоч в одному слоті: інакше міняти в слоті напруги
#                    нема чого (це означення, не поріг);
#   · розрив       — наявність речі на гілці `ГІЛКА_РОЗРИВ` (теж означення);
#   · фільтр-і-ранг — непорожній пул.
# ЩО ЦЕ НЕ РОБИТЬ: не додає в пул жодної речі й не послаблює вікон. Полюс, якого
# пул не несе, лишається недосяжним — правило лише забороняє ВДАВАТИ, що він є.
_ПОЛЮС_ЗАВЖДИ = "фільтр-і-ранг"


def полюси_пулу(по_слотах, базові=("верх", "низ", "сукня", "комплект")):
    """{ід полюса: dict(є, чому)} — які задуми цей пул спроможний дати.

    `по_слотах` — кандидати ПІСЛЯ семплера, тобто рівно ті речі, які побачить
    модель. Ключі збігаються з `pipeline.ПОЛЮСИ_ОБРАЗУ`; полюс, якого тут нема,
    вважається доступним (словник полюсів росте не тут, і мовчазне «нема» зробило
    б із появи нового полюса його ж зникнення)."""
    import colorspace as _cs, реєстр_правил as _РЕЄСТР
    речі = [r for пул in (по_слотах or {}).values() for r in (пул or ())]
    непорожніх = [с for с, пул in (по_слотах or {}).items() if пул]
    виразні = [r for r in речі if _виразність(r) >= _РЕЄСТР.C["виразність_героя"]]
    # ДВІ ФОРМИ ОДНОГО РЯДКА, І ОБИДВІ ЗАКОННІ. Функцію кличуть і над речами
    # композитора (`_у_річ`: `_гілка`, `lab`), і над рядком, який їде МОДЕЛІ
    # (`pipeline._річ_пулу`: `гілка`, `hex`) — а саме там і вирішується, що
    # замовити. Читати лише одну форму означало б мовчки віддавати «нема полюса»
    # на другій, тобто відповідати на питання «чи пул несе розрив» тим, із якого
    # боку спитали.
    _гілка_р = lambda r: r.get("_гілка") or r.get("гілка")
    розривні = [r for r in речі if _гілка_р(r) == ГІЛКА_РОЗРИВ]
    з_двома = [с for с, пул in (по_слотах or {}).items() if len(пул or ()) >= 2]
    # КОЛОНА: пара речей РІЗНИХ базових слотів, чиї світлоти різняться менш ніж на
    # крок Munsell. Саме це й означає «тональна колона» — око не бачить межі між
    # ними; більша різниця вже є структурою світлоти (K-COL-01), а не колоною.
    крок = _РЕЄСТР.C["step_min"]
    L_за_слотом = {}
    for с in (по_слотах or {}):
        if с not in базові:
            continue
        for r in (по_слотах[с] or ()):
            lab = r.get("lab")
            if lab is None and r.get("hex"):
                try: lab = _cs.hx(r["hex"])
                except Exception: lab = None
            if lab:
                try: L_за_слотом.setdefault(с, []).append(float(_cs.lch(tuple(lab))[0]))
                except Exception: pass
    колона = False
    слоти_L = [с for с in L_за_слотом if L_за_слотом[с]]
    for i in range(len(слоти_L)):
        for j in range(i + 1, len(слоти_L)):
            a, b = sorted(L_за_слотом[слоти_L[i]]), sorted(L_за_слотом[слоти_L[j]])
            if any(abs(x - y) < крок for x in a for y in b):
                колона = True; break
        if колона:
            break
    return {
        _ПОЛЮС_ЗАВЖДИ: dict(є=bool(речі),
                            чому="пул порожній" if not речі
                                 else "%d речей у %d слотах" % (len(речі), len(непорожніх))),
        "якір першим": dict(є=bool(виразні),
            чому=("виразних речей (≥ %.1f за `_виразність`) %d" % (_РЕЄСТР.C["виразність_героя"], len(виразні)))
                 if виразні else
                 "у пулі нема жодної речі з виразністю ≥ %.1f: ані принту, ані повної "
                 "хроми, ані помітної поверхні — якоря взяти нема з чого"
                 % _РЕЄСТР.C["виразність_героя"]),
        "тональна колона": dict(є=колона,
            чому=("є пара базових слотів зі світлотами ближче за крок Munsell (%.0f)" % крок)
                 if колона else
                 "жодна пара базових слотів не дає світлот ближчих за крок Munsell "
                 "(%.0f): колона з цього пулу не збирається — вона була б структурою "
                 "світлоти, а не колоною" % крок),
        "послабити вузол": dict(є=len(з_двома) >= 1,
            чому=("слотів із ≥2 кандидатами %d" % len(з_двома)) if з_двома else
                 "у кожному слоті рівно один кандидат: у вузлі напруги міняти нема чого"),
        "розрив": dict(є=bool(розривні),
            чому=("речей на гілці «розрив» %d" % len(розривні)) if розривні else
                 "у пулі нема жодної речі поза вікнами палітри (гілка «розрив»): "
                 "оголошувати розрив нема чим, і замовлення на нього виконується "
                 "лише ще однією варіацією середини"),
    }


def _портфель(оцінені, найкраще, слоти, вузол=None):
    """K-VAR-01 (тема-4 XIII): портфель із 2–3 образів РІЗНИХ полюсів замість «наступних за
    порядком». ЩО ЦЕ МІНЯЄ: «альтернативи» композитора на ager були тим самим топом із іншими
    штанами — п'ять варіацій однієї відповіді, рівно те, що правило зве провалом. Тут:
      O1 — переможець ранжування (як було);
      O2 — ЯКІР ПЕРШИМ (K-COMP-02): найвиразніша річ пулу, якої нема в O1, і найкраща
           комбінація навколо неї;
      O3 — ПАЛІТРА ПЕРШОЮ / колона: найузгодженіша за кольором чиста комбінація, що
           відрізняється від O1 (тональний полюс — протилежний до середини K-COMP-01).
    Кожен образ портфеля мусить відрізнятись від O1 хоч в одному слоті — інакше він не
    полюс, а дубль, і не видається. Порядок усередині портфеля — не оцінка (R-ABC-08)."""
    import trace as _СЛ
    def імена(x): return tuple((r.get("назва") or r.get("id")) for r in x["речі"])
    def інший(x): return імена(x) != імена(найкраще)
    def верх_знахідок(x):
        # дві найсильніші знахідки полюса — щоб тональна колона не виглядала «чистою»,
        # коли K-COL-01 називає її площинною
        зн = sorted([z for z in x["знахідки"] if z.get("правило") and z.get("сила_нп")],
                    key=lambda z: -(z.get("сила_нп") or 0))[:2]
        return [(z["правило"], z.get("сила_нп"), str(z.get("суть", ""))[:50]) for z in зн]
    вих = [dict(оператор="O1 фільтр-і-ранг", чому="переможець ранжування", речі=list(імена(найкраще)),
                ід=[r.get("id") for r in найкраще["речі"]], блокує=найкраще["блокує"],
                знахідки=верх_знахідок(найкраще))]
    # O2: якір = найвиразніша річ, якої нема у переможцеві
    у_переможці = {r.get("id") for r in найкраще["речі"]}
    кандидати = {}
    for x in оцінені:
        for r in x["речі"]:
            if r.get("id") not in у_переможці:
                кандидати[r.get("id")] = r
    if кандидати:
        якір = max(кандидати.values(), key=_виразність)
        навколо = [x for x in оцінені if any(r.get("id") == якір.get("id") for r in x["речі"]) and інший(x)]
        if навколо:
            x2 = навколо[0]   # оцінені вже впорядковані
            вих.append(dict(оператор="O2 якір першим (K-COMP-02)",
                            чому="якір «%s» (виразність %.2f) — решта слотів навколо нього" % (якір.get("назва") or якір.get("id"), _виразність(якір)),
                            речі=list(імена(x2)), ід=[r.get("id") for r in x2["речі"]],
                            блокує=x2["блокує"], знахідки=верх_знахідок(x2)))
            _СЛ.запис("K-COMP-02", "якір першим: %s" % (якір.get("назва") or якір.get("id"))[:40],
                      "composer._портфель", значення="виразність %.2f" % _виразність(якір), сила=None, напрям="полюс O2")
    # O3: тональна колона — найузгодженіша (найменша середня відстань), чиста, інша
    з_відст = [x for x in оцінені if x.get("близькість") is not None and not x["блокує"] and інший(x)
               and імена(x) not in {tuple(v["речі"]) for v in вих}]
    if з_відст:
        x3 = min(з_відст, key=lambda x: x["близькість"])
        вих.append(dict(оператор="O3 палітра першою (колона)",
                        чому="найузгодженіша чиста комбінація (d_ok %.3f) — тональний полюс" % x3["близькість"],
                        речі=list(імена(x3)), ід=[r.get("id") for r in x3["речі"]],
                        блокує=x3["блокує"], знахідки=верх_знахідок(x3)))
    # O4: ПОСЛАБИТИ ВУЗЬКИЙ ВУЗОЛ — альтернатива, що міняє САМЕ слот напруги
    # переможця й тримає решту (28.08.2026, graph.py). Це відповідь на «чому не
    # інший низ?», якої сума сил дати не могла: полюс визначає не найкращий
    # ключ, а найменша напруга в тому вузлі, де переможцю вузько.
    if вузол and вузол.get("вузол") in СЛОТИ_ГРАФА:
        с = вузол["вузол"]
        інші_слоти = {r.get("id") for r in найкраще["речі"] if r.get("слот") != с}
        кандидати4 = [x for x in оцінені if інший(x) and імена(x) not in {tuple(v["речі"]) for v in вих}
                      and {r.get("id") for r in x["речі"] if r.get("слот") != с} == інші_слоти
                      and not x["блокує"]]
        if кандидати4:
            def напруга_вузла(x):
                в = next((v for v in x["граф"]["вузли"] if v["вузол"] == с), None)
                return в["напруга"] if в else 0.0
            x4 = min(кандидати4, key=lambda x: (напруга_вузла(x), x["ключ"]))
            if напруга_вузла(x4) < вузол["напруга"]:
                вих.append(dict(оператор="O4 послабити вузол «%s»" % с,
                                чому="той самий образ, інший «%s»: напруга вузла %.2f → %.2f"
                                     % (с, вузол["напруга"], напруга_вузла(x4)),
                                речі=list(імена(x4)), ід=[r.get("id") for r in x4["речі"]],
                                блокує=x4["блокує"], знахідки=верх_знахідок(x4)))
                _СЛ.запис("K-VAR-01", "послаблено вузол «%s»" % с, "composer._портфель",
                          значення="%.2f → %.2f" % (вузол["напруга"], напруга_вузла(x4)), сила=None, напрям="полюс O4")
    полюсів = len(вих)
    _СЛ.запис("K-VAR-01", "портфель: %d полюс(и)" % полюсів, "composer._портфель",
              значення="; ".join(v["оператор"] for v in вих), сила=None,
              напрям=("виконано" if полюсів >= 2 else "лише один образ — полюсів у пулі нема"))
    # O5: РОЗРИВ — найкращий чистий образ, у якому слот розриву взято ПОЗА палітрою
    # (сміливий намір; 28.08.2026). Полюс існує, лише коли такий образ є в оцінених.
    розривні = [x for x in оцінені if not x["блокує"] and інший(x)
                and any(r.get("_гілка") == ГІЛКА_РОЗРИВ for r in x["речі"])
                and імена(x) not in {tuple(v["речі"]) for v in вих}]
    if розривні:
        x5 = розривні[0]   # оцінені впорядковані ключем
        річ5 = next(r for r in x5["речі"] if r.get("_гілка") == ГІЛКА_РОЗРИВ)
        вих.append(dict(оператор="O5 розрив (поза палітрою)",
                        чому="слот «%s» узято поза вікнами палітри — «%s»; решта тримає ядро" % (річ5.get("слот"), (річ5.get("назва") or річ5.get("id") or "")[:40]),
                        речі=list(імена(x5)), ід=[r.get("id") for r in x5["речі"]],
                        блокує=x5["блокує"], знахідки=верх_знахідок(x5), розрив=річ5.get("id")))
    return вих


def _пояснити(найкраще, усі, ноти, вузол=None, резон=()):
    рядки = []
    if найкраще["блокує"]:
        рядки.append("ЖОДНА комбінація не пройшла без блокувань — показано найменш "
                     "порушну. Блокери: %s" % "; ".join(найкраще["блокери"][:2]))
    else:
        рядки.append("пройшла без жодного блокувального спрацювання")
    # ЯРЛИК НАЗИВАВ НЕ ТЕ ЧИСЛО (07.09.2026). Тут стояло `.get("сума_розр", …)`, а
    # `сума_розр` не пише НІХТО в усьому дереві — тобто запасне значення спрацьовувало
    # завжди, і рядок «сума розрізнювальних сил» друкував суму ВСІХ сил. Різниця не
    # косметична: розрізнювальні — це ті правила, чия напруга різниться між
    # комбінаціями (означення з `graph`), і саме вони впорядковують пул; резонансні
    # у сумі є, а пулу не впорядковують. Числа «лише розрізнювальні» система не
    # рахує, тому воно й не називається — вигадати його тут було б гірше.
    рядки.append("сума сил знахідок %.2f (ключ сортування, НЕ оцінка; "
                 "резонансні входять у неї, хоч пулу не впорядковують)"
                 % найкраще["сума_сил"])
    _рв = ГР.рядок_вузла(вузол, найкраще["граф"]) if найкраще.get("граф") else None
    if _рв: рядки.append(_рв)
    if резон:
        рядки.append("не розрізняють у цьому пулі (резонанс, не критерій): %s" % ", ".join(sorted(резон)))
    if найкраще["середня_відстань"] is not None:
        рядки.append("середня ΔE00 до центрів вікон %.2f" % найкраще["середня_відстань"])
    for сл, н in ноти.items():
        рядки.append("слот «%s»: %s" % (сл, н))
    return рядки
