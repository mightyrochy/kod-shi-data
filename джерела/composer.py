# ── ЧИ ПУЛ ВЗАГАЛІ НЕСЕ ПОЛЮСИ, ЯКІ ПАКЕТ ОБІЦЯЄ (K-VAR-01, 17.09.2026) ─────
# ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after, виміряно на `каталог_повний.xml`,
# `bridge.запити` з `варіантів=6`, сцена «офіс · 18 °C»).
#   before — `pipeline.пакет_для_моделі` називає перші N полюсів зі свого словника
#            БЕЗУМОВНО, не питаючи, чи пул їх витримує. Вимір: пакет оголошував
#            шість полюсів, і серед них «розрив» («одна річ навмисно поза
#            палітрою»), а в пулі з 383 речей на гілці «розрив» стояло РІВНО НУЛЬ —
#            усі 383 були «ядро». Тобто моделі замовляли образ із речі, якої в пулі
#            нема. Виконати таке замовлення можна одним способом: віддати ще одну
#            варіацію тієї самої серединної відповіді — рівно те, що K-VAR-01 зве
#            провалом («a single stereotype per request is a failure»).
#   after  — пакет називає лише ті полюси, які пул СПРОМОЖНИЙ дати, а решту
#            називає вголос окремим рядком вимог: «нема речі» ≠ «полюс не
#            потрібен». Незайняті місця стають ВІЛЬНИМИ задумами, а не мовчазними
#            дублями.
# ЖОДНОЇ НОВОЇ КОНСТАНТИ ТУТ НЕМА, І ЦЕ НАВМИСНО. Кожен предикат стоїть на числі,
# яке вже оголошене зі своїм тіром:
#   · якір         — `виразність_героя` (T3, K-COMP-02), та сама шкала `_виразність`;
#   · колона       — `step_min` (T2, K-COL-01, крок Munsell): колона читається
#                    колоною, поки сусідні світлоти РІЗНЯТЬСЯ МЕНШ ніж на крок;
#   · вузол        — ≥2 кандидати хоч в одному слоті: інакше міняти в слоті напруги
#                    нема чого (це означення, не поріг);
#   · розрив       — наявність речі на гілці `ГІЛКА_РОЗРИВ` (теж означення);
#   · фільтр-і-ранг — непорожній пул.
# ЩО ЦЕ НЕ РОБИТЬ: не додає в пул жодної речі й не послаблює вікон. Полюс, якого
# пул не несе, лишається недосяжним — правило лише забороняє ВДАВАТИ, що він є.
_ПОЛЮС_ЗАВЖДИ = "фільтр-і-ранг"


def _ключ_ранжування(x):
    """Ключ порядку комбінацій. Винесений із `sort(key=…)` НАВМИСНО: він несе
    архітектурне твердження K-P0-01 («посадка — гейт, не критерій з вагою»), а
    твердження, яке не можна назвати на ім'я, не можна й перевірити пробою."""
    return (1 if x.get("блок_посадки") else 0,
            x["блокує"], x["сума_сил"],
            tuple(r.get("id") or "" for r in x.get("речі") or ()))


def полюси_пулу(по_слотах, базові=("верх", "низ", "сукня", "комплект")):
    """{ід полюса: dict(є, чому)} — які задуми цей пул спроможний дати.

    `по_слотах` — кандидати ПІСЛЯ семплера, тобто рівно ті речі, які побачить
    модель. Ключі збігаються з `pipeline.ПОЛЮСИ_ОБРАЗУ`; полюс, якого тут нема,
    вважається доступним (словник полюсів росте не тут, і мовчазне «нема» зробило
    б із появи нового полюса його ж зникнення)."""
    import colorspace as _cs, реєстр_правил as _РЕЄСТР
    речі = [r for пул in (по_слотах or {}).values() for r in (пул or ())]
    непорожніх = [с for с, пул in (по_слотах or {}).items() if пул]
    виразні = [r for r in речі if _виразність(r) >= _РЕЄСТР.C["виразність_героя"]]
    # ДВІ ФОРМИ ОДНОГО РЯДКА, І ОБИДВІ ЗАКОННІ. Функцію кличуть і над речами
    # композитора (`_у_річ`: `_гілка`, `lab`), і над рядком, який їде МОДЕЛІ
    # (`pipeline._річ_пулу`: `гілка`, `hex`) — а саме там і вирішується, що
    # замовити. Читати лише одну форму означало б мовчки віддавати «нема полюса»
    # на другій, тобто відповідати на питання «чи пул несе розрив» тим, із якого
    # боку спитали.
    _гілка_р = lambda r: r.get("_гілка") or r.get("гілка")
    розривні = [r for r in речі if _гілка_р(r) == ГІЛКА_РОЗРИВ]
    з_двома = [с for с, пул in (по_слотах or {}).items() if len(пул or ()) >= 2]
    # КОЛОНА: пара речей РІЗНИХ базових слотів, чиї світлоти різняться менш ніж на
    # крок Munsell. Саме це й означає «тональна колона» — око не бачить межі між
    # ними; більша різниця вже є структурою світлоти (K-COL-01), а не колоною.
    крок = _РЕЄСТР.C["step_min"]
    L_за_слотом = {}
    for с in (по_слотах or {}):
        if с not in базові:
            continue
        for r in (по_слотах[с] or ()):
            lab = r.get("lab")
            if lab is None and r.get("hex"):
                try: lab = _cs.hx(r["hex"])
                except Exception: lab = None
            if lab:
                try: L_за_слотом.setdefault(с, []).append(float(_cs.lch(tuple(lab))[0]))
                except Exception: pass
    колона = False
    слоти_L = [с for с in L_за_слотом if L_за_слотом[с]]
    for i in range(len(слоти_L)):
        for j in range(i + 1, len(слоти_L)):
            a, b = sorted(L_за_слотом[слоти_L[i]]), sorted(L_за_слотом[слоти_L[j]])
            if any(abs(x - y) < крок for x in a for y in b):
                колона = True; break
        if колона:
            break
    return {
        _ПОЛЮС_ЗАВЖДИ: dict(є=bool(речі),
                            чому="пул порожній" if not речі
                                 else "%d речей у %d слотах" % (len(речі), len(непорожніх))),
        "якір першим": dict(є=bool(виразні),
            чому=("виразних речей (≥ %.1f за `_виразність`) %d" % (_РЕЄСТР.C["виразність_героя"], len(виразні)))
                 if виразні else
                 "у пулі нема жодної речі з виразністю ≥ %.1f: ані принту, ані повної "
                 "хроми, ані помітної поверхні — якоря взяти нема з чого"
                 % _РЕЄСТР.C["виразність_героя"]),
        "тональна колона": dict(є=колона,
            чому=("є пара базових слотів зі світлотами ближче за крок Munsell (%.0f)" % крок)
                 if колона else
                 "жодна пара базових слотів не дає світлот ближчих за крок Munsell "
                 "(%.0f): колона з цього пулу не збирається — вона була б структурою "
                 "світлоти, а не колоною" % крок),
        "послабити вузол": dict(є=len(з_двома) >= 1,
            чому=("слотів із ≥2 кандидатами %d" % len(з_двома)) if з_двома else
                 "у кожному слоті рівно один кандидат: у вузлі напруги міняти нема чого"),
        "розрив": dict(є=bool(розривні),
            чому=("речей на гілці «розрив» %d" % len(розривні)) if розривні else
                 "у пулі нема жодної речі поза вікнами палітри (гілка «розрив»): "
                 "оголошувати розрив нема чим, і замовлення на нього виконується "
                 "лише ще однією варіацією середини"),
    }


def _портфель(оцінені, найкраще, слоти, вузол=None):
    """K-VAR-01 (тема-4 XIII): портфель із 2–3 образів РІЗНИХ полюсів замість «наступних за
    порядком». ЩО ЦЕ МІНЯЄ: «альтернативи» композитора на ager були тим самим топом із іншими
    штанами — п'ять варіацій однієї відповіді, рівно те, що правило зве провалом. Тут:
      O1 — переможець ранжування (як було);
      O2 — ЯКІР ПЕРШИМ (K-COMP-02): найвиразніша річ пулу, якої нема в O1, і найкраща
           комбінація навколо неї;
      O3 — ПАЛІТРА ПЕРШОЮ / колона: найузгодженіша за кольором чиста комбінація, що
           відрізняється від O1 (тональний полюс — протилежний до середини K-COMP-01).
    Кожен образ портфеля мусить відрізнятись від O1 хоч в одному слоті — інакше він не
    полюс, а дубль, і не видається. Порядок усередині портфеля — не оцінка (R-ABC-08)."""
    import trace as _СЛ
    def імена(x): return tuple((r.get("назва") or r.get("id")) for r in x["речі"])
    def інший(x): return імена(x) != імена(найкраще)
    def верх_знахідок(x):
        # дві найсильніші знахідки полюса — щоб тональна колона не виглядала «чистою»,
        # коли K-COL-01 називає її площинною
        зн = sorted([z for z in x["знахідки"] if z.get("правило") and z.get("сила_нп")],
                    key=lambda z: -(z.get("сила_нп") or 0))[:2]
        return [(z["правило"], z.get("сила_нп"), str(z.get("суть", ""))[:50]) for z in зн]
    вих = [dict(оператор="O1 фільтр-і-ранг", чому="переможець ранжування", речі=list(імена(найкраще)),
                ід=[r.get("id") for r in найкраще["речі"]], блокує=найкраще["блокує"],
                знахідки=верх_знахідок(найкраще))]
    # O2: якір = найвиразніша річ, якої нема у переможцеві
    у_переможці = {r.get("id") for r in найкраще["речі"]}
    кандидати = {}
    for x in оцінені:
        for r in x["речі"]:
            if r.get("id") not in у_переможці:
                кандидати[r.get("id")] = r
    if кандидати:
        якір = max(кандидати.values(), key=_виразність)
        навколо = [x for x in оцінені if any(r.get("id") == якір.get("id") for r in x["речі"]) and інший(x)]
        if навколо:
            x2 = навколо[0]   # оцінені вже впорядковані
            вих.append(dict(оператор="O2 якір першим (K-COMP-02)",
                            чому="якір «%s» (виразність %.2f) — решта слотів навколо нього" % (якір.get("назва") or якір.get("id"), _виразність(якір)),
                            речі=list(імена(x2)), ід=[r.get("id") for r in x2["речі"]],
                            блокує=x2["блокує"], знахідки=верх_знахідок(x2)))
            _СЛ.запис("K-COMP-02", "якір першим: %s" % (якір.get("назва") or якір.get("id"))[:40],
                      "composer._портфель", значення="виразність %.2f" % _виразність(якір), сила=None, напрям="полюс O2")
    # O3: тональна колона — найузгодженіша (найменша середня відстань), чиста, інша
    з_відст = [x for x in оцінені if x.get("близькість") is not None and not x["блокує"] and інший(x)
               and імена(x) not in {tuple(v["речі"]) for v in вих}]
    if з_відст:
        x3 = min(з_відст, key=lambda x: x["близькість"])
        вих.append(dict(оператор="O3 палітра першою (колона)",
                        чому="найузгодженіша чиста комбінація (d_ok %.3f) — тональний полюс" % x3["близькість"],
                        речі=list(імена(x3)), ід=[r.get("id") for r in x3["речі"]],
                        блокує=x3["блокує"], знахідки=верх_знахідок(x3)))
    # O4: ПОСЛАБИТИ ВУЗЬКИЙ ВУЗОЛ — альтернатива, що міняє САМЕ слот напруги
    # переможця й тримає решту (28.08.2026, graph.py). Це відповідь на «чому не
    # інший низ?», якої сума сил дати не могла: полюс визначає не найкращий
    # ключ, а найменша напруга в тому вузлі, де переможцю вузько.
    if вузол and вузол.get("вузол") in СЛОТИ_ГРАФА:
        с = вузол["вузол"]
        інші_слоти = {r.get("id") for r in найкраще["речі"] if r.get("слот") != с}
        кандидати4 = [x for x in оцінені if інший(x) and імена(x) not in {tuple(v["речі"]) for v in вих}
                      and {r.get("id") for r in x["речі"] if r.get("слот") != с} == інші_слоти
                      and not x["блокує"]]
        if кандидати4:
            def напруга_вузла(x):
                в = next((v for v in x["граф"]["вузли"] if v["вузол"] == с), None)
                return в["напруга"] if в else 0.0
            x4 = min(кандидати4, key=lambda x: (напруга_вузла(x), x["ключ"]))
            if напруга_вузла(x4) < вузол["напруга"]:
                вих.append(dict(оператор="O4 послабити вузол «%s»" % с,
                                чому="той самий образ, інший «%s»: напруга вузла %.2f → %.2f"
                                     % (с, вузол["напруга"], напруга_вузла(x4)),
                                речі=list(імена(x4)), ід=[r.get("id") for r in x4["речі"]],
                                блокує=x4["блокує"], знахідки=верх_знахідок(x4)))
                _СЛ.запис("K-VAR-01", "послаблено вузол «%s»" % с, "composer._портфель",
                          значення="%.2f → %.2f" % (вузол["напруга"], напруга_вузла(x4)), сила=None, напрям="полюс O4")
    полюсів = len(вих)
    _СЛ.запис("K-VAR-01", "портфель: %d полюс(и)" % полюсів, "composer._портфель",
              значення="; ".join(v["оператор"] for v in вих), сила=None,
              напрям=("виконано" if полюсів >= 2 else "лише один образ — полюсів у пулі нема"))
    # O5: РОЗРИВ — найкращий чистий образ, у якому слот розриву взято ПОЗА палітрою
    # (сміливий намір; 28.08.2026). Полюс існує, лише коли такий образ є в оцінених.
    розривні = [x for x in оцінені if not x["блокує"] and інший(x)
                and any(r.get("_гілка") == ГІЛКА_РОЗРИВ for r in x["речі"])
                and імена(x) not in {tuple(v["речі"]) for v in вих}]
    if розривні:
        x5 = розривні[0]   # оцінені впорядковані ключем
        річ5 = next(r for r in x5["речі"] if r.get("_гілка") == ГІЛКА_РОЗРИВ)
        вих.append(dict(оператор="O5 розрив (поза палітрою)",
                        чому="слот «%s» узято поза вікнами палітри — «%s»; решта тримає ядро" % (річ5.get("слот"), (річ5.get("назва") or річ5.get("id") or "")[:40]),
                        речі=list(імена(x5)), ід=[r.get("id") for r in x5["речі"]],
                        блокує=x5["блокує"], знахідки=верх_знахідок(x5), розрив=річ5.get("id")))
    return вих


def _пояснити(найкраще, усі, ноти, вузол=None, резон=()):
    рядки = []
    if найкраще["блокує"]:
        рядки.append("ЖОДНА комбінація не пройшла без блокувань — показано найменш "
                     "порушну. Блокери: %s" % "; ".join(найкраще["блокери"][:2]))
    else:
        рядки.append("пройшла без жодного блокувального спрацювання")
    # ЯРЛИК НАЗИВАВ НЕ ТЕ ЧИСЛО (07.09.2026). Тут стояло `.get("сума_розр", …)`, а
    # `сума_розр` не пише НІХТО в усьому дереві — тобто запасне значення спрацьовувало
    # завжди, і рядок «сума розрізнювальних сил» друкував суму ВСІХ сил. Різниця не
    # косметична: розрізнювальні — це ті правила, чия напруга різниться між
    # комбінаціями (означення з `graph`), і саме вони впорядковують пул; резонансні
    # у сумі є, а пулу не впорядковують. Числа «лише розрізнювальні» система не
    # рахує, тому воно й не називається — вигадати його тут було б гірше.
    рядки.append("сума сил знахідок %.2f (ключ сортування, НЕ оцінка; "
                 "резонансні входять у неї, хоч пулу не впорядковують)"
                 % найкраще["сума_сил"])
    _рв = ГР.рядок_вузла(вузол, найкраще["граф"]) if найкраще.get("граф") else None
    if _рв: рядки.append(_рв)
    if резон:
        рядки.append("не розрізняють у цьому пулі (резонанс, не критерій): %s" % ", ".join(sorted(резон)))
    if найкраще["середня_відстань"] is not None:
        рядки.append("середня ΔE00 до центрів вікон %.2f" % найкраще["середня_відстань"])
    for сл, н in ноти.items():
        рядки.append("слот «%s»: %s" % (сл, н))
    return рядки
