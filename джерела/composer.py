def _підпул(пул, k):
    """Перші k речей КОЖНОЇ гілки (ядро / на межі / розрив), а не перші k списку.

    Простий зріз `пул[:k]` був би хибний під сміливим наміром: гілки стоять у
    хвості (ядро + межа + розрив конкатенацією), і зріз лишив би саме ядро —
    тобто намір знову перестав би доходити до вибору, а це вже виправлений
    дефект (28.08, «пул і переможець ІДЕНТИЧНІ в усіх 6 сценах»).
    """
    з_гілок, лічильник = [], {}
    for r in пул:
        г = r.get("_гілка") or ГІЛКА_ЯДРО
        n = лічильник.get(г, 0)
        if n >= k: continue
        лічильник[г] = n + 1
        з_гілок.append(r)
    return з_гілок


def _перемішати(послідовність, сід, мітка):
    """Перемішати НА МІСЦІ — і лише якщо прогін назвав сід.

    `сід=0` — не «нульовий сід», а «сіда нема»: тести й CLI мають діставати ту
    саму відповідь, що й до появи цього механізму, інакше червоне в регресії
    перестає означати «зламано». Стенд свій сід шле завжди.

    Рядковий сід, не число: `hash()` рядків у CPython рандомізується між
    процесами (PYTHONHASHSEED), і «відтворюваний» сід був би відтворюваним лише
    в межах одного запуску. `random.Random(рядок)` бере sha512 — стабільно.
    """
    if not сід:
        return послідовність
    random.Random("%d|%s" % (сід, мітка)).shuffle(послідовність)
    return послідовність


