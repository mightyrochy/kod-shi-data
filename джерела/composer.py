# яку можна було відсіяти до подачі, — марна робота моделі й марний рядок судді.
# СИЛА ≤ ВЕРИФІКАЦІЯ: межа — не нова константа, а найширший допуск корпусу
# (форм_розкид_макс, K-KOH-02, T3) плюс один крок на «red sneakers» (K-KOH-03):
# річ, яка НЕ здатна стати в межі навіть з обома поблажками, не може бути в
# когерентному образі для цієї сцени. Тип невідомий → річ лишається: невідоме
# не відсіюється (377 речей без типу на тому самому пулі).
def _поза_сценою(речі, сцен):
    """(лишились, геть, діапазон) — речі, чия формальність типу далі від сцени,
    ніж допуск корпусу + 1. Без сцени — нічого не чіпає."""
    сцен = dict(сцен or {})
    if not (сцен.get("місце") or сцен.get("нагода")):
        return речі, [], None
    try:
        д = O.сценарій(місце=сцен.get("місце"), нагода=сцен.get("нагода"),
                       година=сцен.get("година"), темп_c=сцен.get("темп_c"))["діапазон"]
    except Exception:
        return речі, [], None
    # ОШАТНІСТЬ ІЗ ПАСПОРТА ВИПАДКУ ПЕРЕВАЖУЄ ТАБЛИЦЮ (05.09.2026): слова людини — перші
    _о = сцен.get("_ошатність")
    if isinstance(_о, (list, tuple)) and len(_о) == 2:
        try: д = (min(float(_о[0]), float(_о[1])), max(float(_о[0]), float(_о[1])))
        except (TypeError, ValueError): pass
    lo, hi = float(д[0]), float(д[1])
    # ДОПУСК = РОЗКИД КОРПУСУ (K-KOH-02, 2 кроки) БЕЗ «+1 на red sneakers»: свідомий розрив —
    # право моделі через СВІДОМО/«потрібно», не дефолт пулу. Виміряно 05.09: із +1 на весілля
    # (7–9) і в офіс business formal у пул ішли кросівки 33–35 і кеди 21–22.
    доп = float(O.C.get("форм_розкид_макс", 2))
    лиш, геть = [], []
    for r in речі:
        l, h, _ = O.інтервал_типу(r.get("тип"))
        if l is None:
            лиш.append(r); continue
        # взуття — не далі ніж на щабель від рівня образу (K-SHO-01): кросівки в офіс
        # business formal і на весілля проходили при допуску 2 (виміряно 05.09)
        _д = 1.0 if (r.get("слот") == "взуття" or lo >= 7) else доп   # K-SHO-01 для взуття; K-KOH-08 для рівня ≥ 7
        (геть if (h < lo - _д or l > hi + _д) else лиш).append(r)
    return лиш, геть, (lo, hi)


def _придатні(каталог, жорстке_ні, вето, тіло, сцен=None):
    """Абсолютні фільтри ДО будь-якого впорядкування. Порядок значущий: спершу те,
    що людина заборонила (жодних торгів), потім наявність, потім сцена."""
    відкинуто = []
    речі = [r for r in каталог if r.get("available") is not False]
    n0 = len(каталог)
    if n0 - len(речі):
        відкинуто.append(dict(причина="нема в наявності", скільки=n0 - len(речі)))
    речі, _геть, _д = _поза_сценою(речі, сцен)
    if _геть:
        відкинуто.append(dict(причина="формальність типу поза сценою %g–%g далі за допуск корпусу+1" % _д,
                              скільки=len(_геть),
                              типи=sorted({r.get("тип") for r in _геть}),
                              приклади=[x["назва"][:40] for x in _геть[:3]]))
    if жорстке_ні:
        речі, ні = PR.жорстке_ні_фільтр(речі, жорстке_ні)
        if ні: відкинуто.append(dict(причина="жорстке «ні»", скільки=len(ні),
                                     приклади=[x["назва"] for x in ні[:3]]))
    if вето:
        E = O.елементи([dict(r, hex=r.get("hex") or "#808080", площа=0.3, near=0.3)
                        for r in речі])
        чисті, зн = O.вето_покриття(E, вето=вето, тіло=тіло)
        лишились = {e.get("річ") or e.get("id") for e in чисті}
        нові = [r for r in речі if (r.get("id") in лишились or r.get("назва") in лишились)]
        if len(нові) != len(речі):
            відкинуто.append(dict(причина="вето покриття (K-PC-08)",
                                  скільки=len(речі) - len(нові),
                                  приклади=[z["суть"][:40] for z in зн[:3]]))
        речі = нові
    return речі, відкинуто


def _вікна_на_межі(F, слоти, intent, вікна_ядра, source="uncontrolled"):
    """Вікна всіх гілок розвилки цієї людини, крім тієї, чиї вікна вже є ядром.
    Statement-гілки (тріада) — лише під statement/editorial. Схема без специфікації
    (контраст-мисматч) мовчить, а не вигадує вікна."""
    import palette as P
    try:
        р = P.розвилка(O.контраст_особи(F), intent)
    except Exception:
        return []
    ключ = lambda q: (q.get("слот"), q.get("L_min"), q.get("L_max"), q.get("C_min"), q.get("C_max"), q.get("h_from"), q.get("h_to"))
    ядро = {ключ(q) for q in (вікна_ядра or []) if isinstance(q, dict)}
    out = []
    for g in р["гілки"]:
        if g.get("вага") == "statement" and intent not in ("statement", "editorial"): continue
        try:
            вікна = [q for q in P.запит_у_фід(P.специфікація(F, g["схема"], слоти, source=source))
                     if isinstance(q, dict) and q.get("L_min") is not None]
        except Exception:
            continue
        if вікна and all(ключ(q) in ядро for q in вікна): continue      # це і є ядро
        out += [dict(q, _схема=g["схема"], _вага=g.get("вага")) for q in вікна if ключ(q) not in ядро]
    return out


def _влучає(r, q):
    """частка вікна (річ-зона) або точкове влучання; None — річ без кольору."""
    if not r.get("lab"): return None
    try:
        if r.get("вікно"):
            return feed.частка_вікна(r["вікно"], q)
        return 1.0 if feed.підходить(r["lab"], q) else 0.0
    except Exception:
        return None


def _кандидати_гілки(речі, вікна, слот, ядро_ід, гілка, K, сід=0):
    """K речей слота, що влучають у ці вікна, але не в ядро; тег гілки і схема.

    Нічия розв'язується сідом, не порядком каталогу — та сама правка, що в
    `_кандидати_на_слот`; тут вона тримає гілку «на межі» в тому ж режимі, інакше
    сміливий намір лишився б детермінованим при випадковому ядрі."""
    у_слоті = [r for r in речі if r.get("слот") == слот]
    підходящі = []
    for q in вікна:
        if q.get("слот") and q["слот"] != слот: continue
        for r in у_слоті:
            ч = _влучає(r, q)
            if not ч: continue
            d = (1.0 - ч) * 100.0 if r.get("вікно") else feed.відстань_до_центру(r["lab"], q)
            підходящі.append((d, r, q))
    _перемішати(підходящі, сід, слот + "|межа")
    підходящі.sort(key=lambda x: x[0])
    вийшло, бачені = [], set(ядро_ід)
    for d, r, q in підходящі:
        к = r.get("group_id") or r.get("id")
        if к in бачені: continue
        бачені.add(к)
        вийшло.append(dict(r, _відстань=d, _вікно=q, _гілка=гілка, _схема=q.get("_схема")))
        if len(вийшло) >= K: break
    return вийшло


def _поза_палітрою(речі, вікна_усі, слот, зайняті, сід=0):
    """Речі слота з кольором, що не влучають у ЖОДНЕ вікно, — найдальші від палітри перші.

    Нічия — сідом (див. `_кандидати_на_слот`): «найдальші перші» теж дає плато
    рівних відстаней, і перший у фіді ставав єдиним дозволеним розривом."""
    у_слоті = [r for r in речі if r.get("слот") == слот and r.get("lab")]
    центри = [q for q in вікна_усі if not q.get("слот") or q["слот"] == слот]
    out, бачені = [], set(зайняті)
    for r in у_слоті:
        к = r.get("group_id") or r.get("id")
        if к in бачені: continue
        if any((_влучає(r, q) or 0) > 0 for q in центри): continue
        try:
            d = min(feed.відстань_до_центру(r["lab"], q) for q in центри) if центри else 0.0
        except Exception:
            continue
        бачені.add(к)
        out.append(dict(r, _відстань=d, _вікно=None, _гілка=ГІЛКА_РОЗРИВ))
    _перемішати(out, сід, слот + "|розрив")
    out.sort(key=lambda r: -(r["_відстань"] or 0))
    return out


