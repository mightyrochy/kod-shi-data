def _координація_з(оцінені, найкраще):
    """Чи координація РОЗРІЗНЯЄ образи — над вибіркою, не над добутком.

    ЩО ЗМІНИЛОСЬ У ПИТАННІ. Доти координація була вагою в цільовій функції коду, і
    питання звучало «чи вона міняє ВЕРШИНУ». Вершини нема: продукт образів не
    впорядковує. Але координація й далі дає знахідки над образом ші, і вони їдуть
    у промпт ремонту — отже питання «чи вона взагалі розводить образи» лишається
    осмисленим. Тут воно й рахується: ключ із нею проти ключа без неї, скільки
    комбінацій змінили ранг.
    """
    if len(оцінені) < 2:
        return dict(вершина_змінилась=False, комбінацій_змінили_ранг=0,
                    чи_розрізняє="вибірка замала для висновку")
    # `набір_кандидатів` — ЧИСЛА близькості пулу, не списки елементів. Перша версія
    # передала сюди елементи, і `розкид_набору` спробував порівняти dict із dict.
    елементи = [O.елементи(x["речі"]) for x in оцінені]
    близькості = [КО.середня_близькість(E) for E in елементи]
    інші = [v for v in близькості if v is not None]
    for x, E, бл in zip(оцінені, елементи, близькості):
        зн = КО.координація(E, набір_кандидатів=інші)
        x["близькість"] = бл
        x["координація"] = round(ВАГА_КООРДИНАЦІЇ * (зн[0]["сила_нп"] or 0.0), 4) \
            if зн and зн[0].get("сила_нп") is not None else 0.0
    без = sorted(range(len(оцінені)), key=lambda i: (оцінені[i]["блокує"], оцінені[i]["сума_сил"], i))
    з = sorted(range(len(оцінені)),
               key=lambda i: (оцінені[i]["блокує"],
                              оцінені[i]["сума_сил"] + оцінені[i]["координація"], i))
    зсув = sum(1 for a, b in zip(без, з) if a != b)
    вершина = без[0] != з[0]
    return dict(
        вершина_змінилась=вершина, комбінацій_змінили_ранг=зсув,
        вага=ВАГА_КООРДИНАЦІЇ,
        близькість_обраного=найкраще.get("близькість"),
        внесок_у_ключ=найкраще.get("координація"),
        # ── ПОЛЕ БУЛО, ЗНАЧЕННЯ НЕ БУЛО (08.09.2026, крок аудиту A7) ────────
        # Тут стояло `діагноз_пулу=None` — тобто поле віддавалось порожнім
        # ЗАВЖДИ. `measure_coordination` його читає (`к["діагноз_пулу"]["чому"]`)
        # і падав TypeError на кожному прогоні; прилад, що міряє, чи координація
        # розрізняє образи, не запускався взагалі.
        # Значення є звідки взяти: `КО.розкид_набору` — та сама функція, якою
        # саме правило вирішує, чи ранг узагалі існує. Вона й відповідає на
        # питання, яке прилад ставив: чи має цей пул колірну варіацію.
        діагноз_пулу=КО.розкид_набору(інші),
        образ_без_координації=[(r.get("слот"), (r.get("назва") or "")[:40])
                               for r in оцінені[без[0]]["речі"]],
        чи_розрізняє=("НІ — жодна комбінація не змінила рангу; правило "
                      "підʼєднане формально" if зсув == 0 else
                      "так: %d із %d комбінацій змінили ранг%s"
                      % (зсув, len(оцінені),
                         ", включно з першою" if вершина else ", але перша та сама")))


def _оцінити_комбінації(комбінації, слоти, F, тіло, жорстке_ні, вето, kw):
    """Перший прохід: кожна комбінація — речі, знахідки, блокери."""
    оцінені, перших_чистих = [], None
    # ВІДСТАНЬ ОГЛЯДУ — З НАГОДИ, ОДИН РАЗ НА ВЕСЬ ПРОХІД (K-COND-04). `kw` тут і
    # є сценарій, тож третього джерела правди для `місце`/`формат`/`нагоди` не
    # заводиться. None (сценарій мовчить) лишає ваги такими, якими вони були.
    _дист = _ДИСТ.з_сценарію(dict(місце=kw.get("місце"), формат=kw.get("формат"),
                                  нагода=kw.get("нагода"))).get("дистанція")
    for комбо in комбінації:
        готові = [_у_річ(r, сл, тіло, _дист) for r, сл in zip(комбо, слоти)]
        # ── ВХІД ПЛОЩІ ЗАКРИВАЄТЬСЯ ТУТ, А НЕ В `_у_річ` (Н-outfit-1-081) ────
        # Пʼять колірних правил (K-COL-01/02/05/06, K-COMP-03) були структурно
        # недосяжні, бо `джерело_площі` не ставив НІХТО: `_у_річ` навмисно його не
        # ставить (вигадана площа гірша за мовчання), і це рішення лишається. Вхід
        # закривається з іншого боку: коли краї речей виміряні, площа РАХУЄТЬСЯ з
        # геометрії тіла, і правила перестають мовчати. Виклик стоїть над ЦІЛИМ
        # образом, бо площа — частка образу, і знаменник у підмножині речей хибний
        # (див. `outfit.площі_з_геометрії`). Поки фід не дає довжин, покриття 0 %,
