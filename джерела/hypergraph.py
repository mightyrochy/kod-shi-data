def самоперевірка(intent="conventional"):
    """Прогін before/after на п'яти тілах. Це не тест — це вимір, який
    зобовʼязаний стояти поруч із правилом (покриття ≠ якість)."""
    тіла = [("пісочний", 168, dict(плечі=98, груди=92, талія=72, стегна=100)),
            ("прямокутник", 174, dict(плечі=92, груди=86, талія=64, стегна=96)),
            ("яблуко", 160, dict(плечі=104, груди=104, талія=88, стегна=112)),
            ("груша", 156, dict(плечі=88, груди=98, талія=80, стегна=94)),
            ("трикутник", 170, dict(плечі=100, груди=96, талія=84, стегна=104))]
    out = []
    for імʼя, зр, об in тіла:
        t = ПС.тіло(зр, об)
        сп = S.специфікація(t, intent=intent)
        пр = простір(t, intent=intent)
        out.append(dict(тіло=імʼя, літера=сп["тіло"],
                        було_законних=сп["законних"],
                        було_частка=сп["роздільність"]["частка_законних"],
                        стало_вище_08=пр["роздільність"]["частка_вище_08"],
                        оцінено=пр.get("оцінено"), усе=пр.get("оцінено_все"),
                        кращий=пр.get("кращий_бал"), q50=пр.get("медіанний_бал"),
                        топ_верх=[k["крій"] for k in пр["крої"]["верх"][:3]],
                        топ_низ=[k["крій"] for k in пр["крої"]["низ"][:3]]))
    return out
