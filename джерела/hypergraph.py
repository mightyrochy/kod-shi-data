# -*- coding: utf-8 -*-
"""ОБРАЗ ЯК ГІПЕРГРАФ, СИЛУЕТ ЯК НЕПЕРЕРВНА ФУНКЦІЯ.

ЩО ЦЕ МІНЯЄ В РІШЕННІ НАД РЕАЛЬНОЮ РІЧЧЮ (before/after, виміряно, не переказано).

  ВИМІР 1 — порожній простір. `силует.специфікація` різала простір кроїв трьома
  бінарними гейтами через AND:
        if not (влучає and not зн_форми and not зн_краю): continue
  Прогін п'яти тіл, intent="conventional", 1485 комбінацій кожне:
        пісочний   12.6% законних     прямокутник 12.6%  (тотожні списки кроїв)
        яблуко      0.0%              груша        0.0%
        трикутник   1.3%
  Тобто на двох тілах із п'яти простір ПОРОЖНІЙ, `запит_у_фід` порожній, і бриф
  втрачає весь силуетний блок: модель не дістає про тіло нічого. Вердикт
  «носитиму / ні» на осі припуску отримати неможливо в принципі.

  ВИМІР 2 — чому порожній. Знахідки, що стоять у тому гейті, зареєстровані в
  самому ж модулі як НЕ-БЛОКУВАЛЬНІ:
        силует.РЕГІСТР_ПРАВИЛА = {"K-SIL-01":"репліка", "K-SIL-03":"репліка",
                                  "K-BOD-02":"репліка", "K-CUT-00":"питання"}
  На яблуці комбінація regular+straight дає три знахідки K-BOD-02, усі
  сила="soft", регістр="репліка", блокує=False, сила_нп = 0.65 / 0.29 / 0.29.
  Репліка силою 0.29 викидала комбінацію так само остаточно, як гейт силою 1.0.
  Це і є розрив неперервності: сила ≤ верифікація стоїть у знахідці, а гейт її
  не читає.

  ВИМІР 3 — літера. `влучає = bool({тренд, середина} & set(ціль))` — булеве
  членство над `літера(об)["оцінки"]`, які вже неперервні (A=1.0, X=0.956,
  V=0.0, O=0.0). Континуум округлявся до біта перед порівнянням.

  after — кожна комбінація дістає БАЛ ∈ [0,1]; простір упорядкований і
  порожнім не буває (порожнеча можлива лише від справжнього блокера, і тоді
  вона названа явно, з переліком блокерів). Виміряно на тих самих п'яти тілах —
  див. `самоперевірка()` унизу файлу.

ЧОМУ ГІПЕРГРАФ, А НЕ СПИСОК ПРАВИЛ. Бриф віддає моделі 17–25 речень поспіль.
Речення виглядають незалежними, а не є: «рівно одна зона максимального
інтересу» — це обмеження на ПОТУЖНІСТЬ МНОЖИНИ всіх слотів; «повний об'єм
потребує якоря» в'яже верх+низ+талію+щиколотку; «дві найбільші речі не ділять
образ навпіл» в'яже всі слоти одночасно. Жодне з них не є ребром між двома
вузлами — усі є ГІПЕРРЕБРАМИ над множинами. Модель, що читає їх як список,
не має чим дізнатися, що виконання одного ламає інше.
Тут вони віддаються з явною інцидентністю: який вузол несе скільки ребер і яку
сумарну напругу. Це і є місце, де код і ші доповнюють одне одного: код МІРЯЄ
напругу й каже, ДЕ вузол вузький; ші РОЗВ'ЯЗУЄ його, бо перебір речей у
природній мові — не наша задача.

ЧОГО ЦЕЙ МОДУЛЬ НЕ ЗНАЄ І НЕ ВДАЄ:
  · усі константи силуету — T3 (конвенція практиків), жодна не калібрована на
    золотому наборі. Тому напруга віддається як `сила_нп` знахідки, а мова
    рядків — прохальна, не заборонна. Ребро НЕ дістає права блокувати.
  · тканина в бал не входить: драп не виміряний ніде в системі, і §10.5 прямо
    каже, що вікно ковзання тримається тканиною. Це найімовірніше джерело
    хибних спрацювань, і воно лишається.
  · нагода й формальність у крій не входять (та сама причина, що в
    `силует.специфікація`: типу виробу в системі нема).
  · високе стегно мовчить, поки не виміряне (тема-1 §17.3) — ролі беруться з
    `силует.ролі_зон`, який це вже придушує.
"""

import silhouette as S
import fit as ПС

# ── вага категорії сили. Це НЕ вимір, це шкала переведення бакета в множник ──
# Стеля 0.9 навмисна: жодна репліка не має права занулити комбінацію повністю,
# бо жодна з них не блокує (РЕГІСТР_ПРАВИЛА). Порожнеча дозволена тільки
# справжньому блокеру.
ВАГА_СИЛИ = {"hard": 0.90, "strong": 0.60, "default": 0.40,
             "soft": 0.25, "hint": 0.12, "питання": 0.05}

# Слова для неперервної величини. Модель не виконує «0.42»; вона виконує
# «помітно». Число лишається в дужках — для судді, не для моделі.
def словами(x):
    return ("майже не тисне" if x < 0.15 else
            "злегка" if x < 0.35 else
            "помітно" if x < 0.60 else
            "сильно" if x < 0.82 else "дуже сильно")


def _вага(з):
    return ВАГА_СИЛИ.get(з.get("сила"), 0.25)


def напруга(знахідки):
    """Сукупна напруга набору реплік ∈ [0,1], неперервно.

    Множення доповнень, а не сума: дві репліки по 0.3 не дають 0.6 «дефекту»,
    вони дають 0.48 — бо кожна прибирає частку від ТОГО, ЩО ЛИШИЛОСЬ. Сума тут
    була б неправильна за побудовою: вона перевищує 1 на чотирьох репліках і
    вимагає обрізання, а обрізання — це знову гейт.
    """
    ц = 1.0
    for з in знахідки or ():
        if з.get("блокує"):
            continue                      # блокери рахуються окремо, не тут
        ц *= (1.0 - _вага(з) * float(з.get("сила_нп") or 0.0))
    return round(1.0 - ц, 4)


def влучання(л, цільові):
    """Неперервне влучання літери образу в цільові літери тіла.

    before — `bool({тренд, середина} & set(ціль))`; after — max по оцінках.
    Коли `оцінки` недоступні (стара обгортка), чесно падає у булеве й помічає це.
    """
    оц = (л or {}).get("оцінки") or {}
    if оц and цільові:
        return round(max(float(оц.get(ц, 0.0)) for ц in цільові), 4), "оцінки"
    складові = {(л or {}).get("тренд"), (л or {}).get("середина")} - {"—", None}
    return (1.0 if складові & set(цільові or ()) else 0.0), "булеве (оцінок нема)"


def оцінка(t, речі, intent="conventional", мета="лестити"):
    """Бал однієї комбінації ∈ [0,1] + усе, з чого він складений.

    бал = влучання × (1 − напруга_форми) × (1 − напруга_краю)
    Добуток, бо осі ортогональні: промах по літері не лікується чистим краєм.
    """
    об = S.обгортка(t, речі)
    л = S.літера(об)
    if not л.get("доступно"):
        return None
    ціль = S.ЦІЛЬ_ЛІТЕРИ.get(ПС.зони(t)["ярлик"], ((), ""))[0]
    вл, вл_дж = влучання(л, ціль)
    зн_форми = (S.конкуренція(t, об, intent) + S.об_єм(t, об, intent)
                + S.без_літери(t, об, intent)
                + S.зонні_операції(t, об, intent) + S.нічия_стратегія(t, об, intent))
    зн_краю = ПС.краї(t, речі, intent, мета)
    блокери = [з for з in (зн_форми + зн_краю) if з.get("блокує")]
    нф, нк = напруга(зн_форми), напруга(зн_краю)
    бал = 0.0 if блокери else round(вл * (1 - нф) * (1 - нк), 4)
    return dict(бал=бал, влучання=вл, влучання_джерело=вл_дж,
                напруга_форми=нф, напруга_краю=нк,
                літера=л.get("літера"), блокери=[з["правило"] for з in блокери],
                знахідки=зн_форми + зн_краю)


def _порожньо(повні, блоковані, без_влучання, ціль, ярлик):
    """ЧОМУ простір порожній — від причини, а не від здогаду.

    Було: рядок будувався ОДНИМ способом — «усі комбінації несуть блокер: » плюс
    перелік блокерів по всіх оцінених. На тілі з ярликом «H/X межа» блокерів нуль,
    а простір порожній, і рядок виходив із порожнім переліком: він називав причиною
    те, чого нема. Це не косметика — саме цей рядок читає гілка «жоден крій» у
    `ребра`, тобто неправда їхала б у бриф.
    """
    if блоковані:
        return ("усі комбінації несуть блокер: %s"
                % ", ".join(sorted({b for d in блоковані for b in d["блокери"]})))
    if без_влучання and not ціль:
        return ("жодна комбінація не влучила: для ярлика «%s» цільових літер у "
                "silhouette.ЦІЛЬ_ЛІТЕРИ немає" % ярлик)
    if без_влучання:
        return ("жодна комбінація не влучила в цільові літери %s"
                % ", ".join(ціль))
    if повні:
        return "усі комбінації занулені напругою форми або краю"
    return "жодна комбінація не дала читабельної літери"


def простір(t, intent="conventional", мета="лестити", пара=("верх", "низ"),
            скільки=12, сітка="повна", фікс_крої=None):
    """Упорядкований простір кроїв. Порожнім не буває, поки нема блокера.

    Двоступеневий перебір — не оптимізація заради оптимізації, а вимога стенда:
    повний свіп 1485 комбінацій із чотирма функціями знахідок коштує 0.51 с на
    CPython, а стенд крутить Pyodide на телефоні й робить ДВА свіпи на випадок
    (рука B і рука C на донорському тілі). Тому спершу рахується дешева пара
    (обгортка+літера), і повний набір знахідок їде лише на верхню частину за
    влучанням. Ціна названа: комбінація з низьким влучанням, але ідеально чистою
    формою, у топ не потрапить. Це прийнятно рівно тому, що бал — добуток, і
    низьке влучання все одно тягне бал донизу.
    """
    верх_с, низ_с = пара
    Н = t["висоти"]
    ціль = S.ЦІЛЬ_ЛІТЕРИ.get(ПС.зони(t)["ярлик"], ((), ""))[0]
    кв = [k for k, s in S.КРІЙ_СЛОТ.items() if верх_с in s]
    кн = [k for k, s in S.КРІЙ_СЛОТ.items() if низ_с in s]

    # ── СІТКА. "повна" — 9×3×11×5 = 1485 комбінацій, 1.0 с на CPython. Стенд
    # крутить Pyodide на телефоні й робить два свіпи на випадок, тобто повна
    # сітка коштує там 5–8 с очікування — це не тестовий стенд, це затримка.
    # "крої" фіксує довжину на серединній і міряє 9×11 = 99 комбінацій.
    # ЦІНА НАЗВАНА: ранжування кроїв перестає бачити взаємодію крою з довжиною
    # (широка штанина midi й maxi дістають один бал). Це прийнятно рівно тому,
    # що довжину в брифі тримає ОКРЕМЕ правило `край` (K-FIT-03, ПС.краї), яке
    # рахується на повних висотах і сюди не входить. Тобто відкидається не
    # обмеження, а його дублювання.
    # "довжини" — дзеркальна економія: крої фіксуються переданим ярусом (уже
    # порахованим сіткою "крої"), довжини вільні. 3×5 = 15 комбінацій. Разом із
    # сіткою "крої" це 114 комбінацій замість 1485 — і обидві осі виміряні, а не
    # одна з них згорнута в дефолт.
    if сітка == "довжини":
        кв = [k for k in (фікс_крої or {}).get("верх", кв) if k in кв] or кв
        кн = [k for k in (фікс_крої or {}).get("низ", кн) if k in кн] or кн
    дв = list(S.ДОВЖИНИ_ВЕРХУ) if сітка in ("повна", "довжини") else [S.ДОВЖИНИ_ВЕРХУ[len(S.ДОВЖИНИ_ВЕРХУ) // 2]]
    дн = list(S.ДОВЖИНИ_НИЗУ) if сітка in ("повна", "довжини") else [S.ДОВЖИНИ_НИЗУ[len(S.ДОВЖИНИ_НИЗУ) // 2]]

    груб = []
    for kв in кв:
        for нв, рв in дв:
            for kн in кн:
                for нн, рн in дн:
                    речі = [dict(id="верх", слот=верх_с, крій=kв,
                                 верх_см=Н["плечі"], низ_см=Н[рв]),
                            dict(id="низ", слот=низ_с, крій=kн,
                                 верх_см=Н["талія"], низ_см=Н[рн])]
                    л = S.літера(S.обгортка(t, речі))
                    if not л.get("доступно"):
                        continue
                    вл, _ = влучання(л, ціль)
                    груб.append((вл, речі, kв, нв, kн, нн))
    if not груб:
        return dict(порожньо="жодна комбінація не дала читабельної літери",
                    комбінації=[], перебрано=0, оцінено=0)

    # ── ЧОМУ ВІДСІКАННЯ ЗА МЕЖЕЮ, А НЕ ЗА РАНГОМ ────────────────────────────
    # Повний свіп 1485 комбінацій із чотирма функціями знахідок коштує 0.80 с на
    # CPython; стенд крутить Pyodide на телефоні й робить ДВА свіпи на випадок
    # (рука B і рука C на донорському тілі). Отже частину простору доводиться
    # не рахувати. Відсікання за РАНГОМ («візьми топ-120») зіпсувало б звіт про
    # роздільність: частка вище 0.80 рахувалась би на вже відібраній верхівці й
    # виходила завищеною (виміряно: 0.60 замість справжньої).
    # Тут відсікання за МЕЖЕЮ. Бал = влучання × (1−нф) × (1−нк), обидві дужки
    # ∈ [0,1], отже бал ≤ влучання ЗАВЖДИ. Тому комбінація з влучанням < 0.80
    # не може дати бал ≥ 0.80 — її можна не рахувати, і верхня смуга лишається
    # ТОЧНОЮ, а не оціненою. Решта простору чесно позначається як не рахована.
    ТОЧНА_МЕЖА = 0.80
    груб.sort(key=lambda x: -x[0])
    кандидати = [g for g in груб if g[0] >= ТОЧНА_МЕЖА]
    # плюс хвіст для квантилів: рівномірна підвибірка решти, щоб q10/q50 не
    # рахувались лише по верхівці
    решта = [g for g in груб if g[0] < ТОЧНА_МЕЖА]
    крок_в = max(1, len(решта) // 60)
    вибірка = решта[::крок_в]
    повні = []
    for вл, речі, kв, нв, kн, нн in кандидати + вибірка:
        о = оцінка(t, речі, intent, мета)
        if о is None:
            continue
        повні.append(dict(верх=dict(крій=kв, довжина=нв, поділ_см=round(речі[0]["низ_см"], 1)),
                          низ=dict(крій=kн, довжина=нн, поділ_см=round(речі[1]["низ_см"], 1)),
                          **о))
    повні.sort(key=lambda d: -d["бал"])
    живі = [d for d in повні if d["бал"] > 0]
    # ЛІЧБА БУЛА НЕЧЕСНА: `блоковані = len(повні) − len(живі)` звало блокером
    # КОЖЕН нуль. На тілі «H/X межа» так виходило «блокованих 62» при нулі
    # блокерів — нулі були від влучання=0 (ярлик не мав цільових літер). Три
    # причини нуля різні, і лікуються різним, тож і рахуються окремо.
    блоковані = [d for d in повні if d["блокери"]]
    без_влучання = [d for d in повні if not d["блокери"] and d["влучання"] <= 0]
    топ = живі[:скільки] if живі else повні[:скільки]

    крої_в, крої_н = {}, {}
    for d in живі:
        крої_в[d["верх"]["крій"]] = max(крої_в.get(d["верх"]["крій"], 0), d["бал"])
        крої_н[d["низ"]["крій"]] = max(крої_н.get(d["низ"]["крій"], 0), d["бал"])
    # ТОЙ САМИЙ РАНГ, АЛЕ ПО ВСІХ ОЦІНЕНИХ. `крої` (лише живі) — те, що їде в бриф,
    # і воно лишається як є. Але коли живих нема, `крої` порожні, і разом із ними
    # зникає ЄДИНЕ джерело для гілки «жоден крій» у `ребра`: вона будувалась із
    # того ж поля й тому не спрацьовувала НІКОЛИ (третя ітерація того самого
    # мертвого коду, коміт b66ac21). Тепер у неї є власне джерело: ранг по нульових
    # балах — «найближчі», а не «законні».
    всі_в, всі_н = {}, {}
    for d in повні:
        всі_в[d["верх"]["крій"]] = max(всі_в.get(d["верх"]["крій"], 0), d["бал"])
        всі_н[d["низ"]["крій"]] = max(всі_н.get(d["низ"]["крій"], 0), d["бал"])
    сорт = lambda d: [dict(крій=k, бал=round(v, 3)) for k, v in
                      sorted(d.items(), key=lambda kv: -kv[1])]

    # РОЗДІЛЬНА ЗДАТНІСТЬ ЗВІТУЄТЬСЯ РАЗОМ ІЗ ВИХОДОМ. «Бал > 0» фільтром не є
    # й ним не зветься: у неперервному просторі відсікає не нуль, а ВЕРХНЯ
    # СМУГА. Тому міряється частка простору вище 0.80 — саме вона їде в бриф.
    бали = sorted(x["бал"] for x in повні)
    # ІМʼЯ `кв` вище вже зайняте списком кроїв верху (рядок 154). Тут це квантиль,
    # і одне імʼя на дві незвʼязані речі в одному тілі функції — рівно та форма,
    # з якої беруться помилки при наступній правці.
    _квантиль = lambda p: round(бали[min(len(бали) - 1, int(p * len(бали)))], 3) if бали else 0.0
    верхня = [x for x in повні if x["бал"] >= ТОЧНА_МЕЖА]
    # ТОЧНО: знаменник — увесь простір, чисельник — уся верхня смуга (за межею
    # жодна комбінація сюди потрапити не може, доведено вище).
    частка = round(len(верхня) / max(1, len(груб)), 3)
    return dict(тіло=ПС.зони(t)["ярлик"], цільові_літери=list(ціль),
                перебрано=len(груб), оцінено=len(повні),
                оцінено_все=(len(повні) == len(груб)),
                живих=len(живі), блокованих=len(блоковані),
                без_влучання=len(без_влучання),
                роздільність=dict(
                    частка_вище_08=частка, точна=True,
                    квантилі_вибірка=dict(q10=_квантиль(0.10), q50=_квантиль(0.50), q90=_квантиль(0.90)),
                    чому=("частка ВСЬОГО простору, що доходить у бриф — рахована точно "
                          "(бал ≤ влучання, тож за межею 0.80 нічого не губиться). "
                          "Квантилі — на підвибірці хвоста, і це позначено. "
                          "Якщо частка > 0.45 — верхня смуга не фільтрує (тема-1 §10.4)")),
                медіанний_бал=_квантиль(0.50),
                кращий_бал=round(повні[0]["бал"], 3) if повні else 0.0,
                крої=dict(верх=сорт(крої_в), низ=сорт(крої_н)),
                крої_всі=dict(верх=сорт(всі_в), низ=сорт(всі_н)),
                # ЯРУС ВІДНОСНИЙ, НЕ АБСОЛЮТНИЙ. Спершу тут стояло `бал >= 0.80`,
                # і на яблуці, де кращий бал 0.76, вікно довжин виходило порожнє —
                # тобто та сама хвороба порожнього виходу, від якої цей модуль і
                # робився, поверталась поверхом нижче. Ярус ріжеться від КРАЩОГО
                # балу цього тіла: питання «які довжини найкращі ТУТ», а не «чи
                # дотягує це тіло до нашої шкали».
                довжини=dict(
                    верх=sorted({d["верх"]["поділ_см"] for d in живі
                                 if d["бал"] >= живі[0]["бал"] - 0.03}) if живі else [],
                    низ=sorted({d["низ"]["поділ_см"] for d in живі
                                if d["бал"] >= живі[0]["бал"] - 0.03}) if живі else []),
                комбінації=топ,
                порожньо=(_порожньо(повні, блоковані, без_влучання, ціль,
                                    ПС.зони(t)["ярлик"]) if not живі else None))


# ═══════════════════════ ГІПЕРРЕБРА ═══════════════════════════════════════
# Ребро — це не «правило про річ», а ПРАВИЛО НАД МНОЖИНОЮ вузлів. Вузол —
# або зона тіла, або слот. Одне й те саме правило на різних тілах в'яже різні
# множини, тому ребра будуються від тіла, а не беруться таблицею.

def _ребро(ід, вузли, напруга_, сила, рядок, чому, інверсія=None, джерело=None):
    return dict(ід=ід, вузли=list(вузли), напруга=round(float(напруга_), 3),
                сила=сила, рядок=рядок, чому=чому,
                інверсія=інверсія, джерело=джерело)


def ребра(t, пр=None, intent="conventional"):
    """Гіперребра цього тіла: множина вузлів + неперервна напруга на ній."""
    Р = []
    рз = S.ролі_зон(t)
    о = t["обхвати"]

    # ── 1. ЗОННА РОЛЬ. Ребро в'яже пару зон, а не одну: роль зони визначена
    # ЧЕРЕЗ протилежну (баланс верх↔низ), і сама по собі не існує.
    верх_о, низ_о = max(о["плечі"], о["груди"]), о["стегна"]
    δ = ((низ_о - верх_о) / верх_о) if верх_о else 0.0
    поріг = S.C["перекос_пари"]
    # НЕПЕРЕРВНО: не «широка/вузька/нейтральна», а величина перекосу, насичена
    # на подвоєному порозі. Мітка лишається для звірки, але напруга йде з числа.
    нп = min(1.0, abs(δ) / (2 * поріг)) if поріг else 0.0
    if нп >= 0.10:
        ширша, вужча = ("низ", "верх") if δ > 0 else ("верх", "низ")
        Р.append(_ребро(
            "баланс_пари", ["плечі", "груди", "стегна", "верх", "низ"], нп, "soft",
            f"Баланс: {ширша} {словами(нп)} ширший за {вужча} "
            f"({abs(δ) * 100:.0f}% різниці обхватів). Робочий хід — обʼєм або структура "
            f"на {слота_родовий(вужча)}, чиста лінія на {слота_родовий(ширша)}; облягання "
            f"вужчої зони перекіс не компенсує.",
            f"перекос пари {δ:+.3f} проти порога {поріг} (T3, конвенція)",
            інверсія=(f"Баланс: тримай {ширша} й {вужча} однаково обʼємними — "
                      f"обидві зони роби широкими."),
            джерело="силует.ролі_зон / K-BOD-02, T3"))
    else:
        Р.append(_ребро(
            "баланс_пари", ["плечі", "груди", "стегна", "верх", "низ"], нп, "hint",
            "Баланс верху й низу рівний — перекосу компенсувати нема чого; "
            "форму задає талія, а не пара.",
            f"перекос пари {δ:+.3f} нижчий за поріг {поріг}",
            інверсія="Верх мусить бути помітно обʼємнішим за низ.",
            джерело="силует.ролі_зон / K-BOD-02, T3"))

    # ── 2. ПРИПУСК ПО ЗОНАХ. Опубліковані мінімуми носіння — те, чого в брифі
    # не було НІКОЛИ: `бриф.py` не імпортує `силует` і не має жодної згадки
    # припуску. Тобто увесь перепис осі припуску до тестувальника не доходив.
    # ЛИШЕ ОПУБЛІКОВАНІ ЛАНДМАРКИ. Щиколотка й високе стегно мають у
    # МІН_НОСІННЯ джерело "проксі" (перенесене з зап'ястя й зі стегна), і в бриф
    # вони не йдуть: перенесене число не має права звучати як вимір. Високе
    # стегно до того ж придушене, поки не виміряне (тема-1 §17.3).
    ландмарки = [z for z in ("груди", "талія", "стегна") if о.get(z)]
    рядки_мін = []
    for z in ландмарки:
        см, опубл, нота = S.мінімум_носіння(z)
        if см is None or not опубл:
            continue
        рядки_мін.append((z, см, о[z], нота))
    if рядки_мін:
        частини = ", ".join(f"{z} від {о_z + см:.0f}" for z, см, о_z, _ in рядки_мін)
        Р.append(_ребро(
            "мінімум_носіння", [z for z, *_ in рядки_мін] + ["верх", "низ"], 0.5, "default",
            f"Полотняна річ має припуск носіння понад обхват тіла (см): {частини}. "
            f"Менше — річ не застібається, це не «облягає». Трикотаж не рахується: "
            f"там припуск буває відʼємним за конструкцією.",
            "Threads #221 / конверти Big Four — один голос галузі, T3; числа "
            "опубліковані, але одноголосі, тому право сказати, не право блокувати",
            інверсія=("Річ має щільно облягати тіло: бери обхват впритул, без "
                      "додаткового припуску."),
            джерело="силует.МІН_НОСІННЯ, T3 (опубліковано)"))

    # ── 3. СМУГА ПРИЛЯГАННЯ. П'ять опублікованих смуг на осі дизайн-припуску.
    вік_л = next(л for н, л, _ in S.СМУГИ if н == S.СМУГИ_КОВЗАННЯ[0])
    вік_х = next(х for н, _, х in S.СМУГИ if н == S.СМУГИ_КОВЗАННЯ[-1])
    Р.append(_ребро(
        "смуга_прилягання", ["груди", "талія", "стегна", "верх", "низ"], 0.35, "hint",
        f"Прилягання по речі тримай однакове зверху донизу. Робоче вікно ковзання — "
        f"{вік_л:.0f}–{вік_х:.0f} см понад мінімум носіння; менше — річ облягає, "
        f"більше — намет.",
        "смуги опубліковані (Threads #221); вікно ковзання — конвенція, T3",
        інверсія="Прилягання по речі може вільно мінятись: вгорі впритул, внизу намет.",
        джерело="силует.СМУГИ, T3"))

    # ── 4. ЯКІР ОБʼЄМУ. Гіперребро: об'єм — властивість УСІХ слотів разом,
    # якір — властивість однієї зони. Ребро в'яже їх, і саме тому воно не
    # розкладається на пари.
    Р.append(_ребро(
        "якір_обʼєму", ["верх", "низ", "шар", "талія", "щиколотка"], 0.45, "default",
        f"Обʼємний образ лиши з одним якорем, де тіло видно: талія (пояс, запах, "
        f"заправка) або щиколотка (звужений чи вкорочений низ). Обʼєм без якоря "
        f"читається як «тіла не видно ніде».",
        f"площа обгортки проти площі тіла, поріг {S.C['об_єм_без_якоря']}; "
        f"якір — припуск ≤ {S.C['якір_прилягання']}",
        інверсія="Обʼєм тримай на всіх шарах одразу; прилеглих місць лишати не треба.",
        джерело="силует.об_єм / K-SIL-03, T3, регістр «репліка»"))

    # ── 5. ОДНА ЛІНІЯ. Гіперребро над усіма рівнями контуру.
    Р.append(_ребро(
        "одна_лінія", ["плечі", "груди", "талія", "стегна", "коліно", "щиколотка"],
        0.4, "default",
        "Контур відходить від тіла в ОДНОМУ місці нижче плечей: обʼємний верх і "
        "водночас обʼємний низ дають дві лінії, жодна не читається.",
        f"виразність відльоту, поріг {S.C['виразність_відльоту']}",
        інверсія="Хай контур відходить від тіла у двох-трьох різних місцях.",
        джерело="силует.конкуренція / K-SIL-01, T3, регістр «репліка»"))

    # ── 6. КРОЇ З БАЛОМ. Не список законних, а ранжування — бо простір
    # неперервний і «законне/незаконне» в ньому не визначене.
    if пр and пр.get("крої"):
        for слот in ("верх", "низ"):
            усі = [k for k in пр["крої"].get(слот, []) if k["бал"] > 0]
            # ДЖЕРЕЛО РІЗНЕ НАВМИСНО: `усі` — живі крої (те, що радиться), а
            # `якщо_нема` — ранг по ВСІХ оцінених. Обидва бралися з `крої`, і саме
            # тому друга гілка була мертва: коли живих нема, `крої` порожні.
            якщо_нема = [k["крій"] for k in (пр.get("крої_всі") or {}).get(слот, [])[:3]]
            if усі:
                # ВЕРХНІЙ ЯРУС, А НЕ П'ЯТІРКА. Виміряно: на пісочному п'ять кроїв
                # низу мали бал 1.00 рівно — друк «straight (1.00), tapered (1.00),
                # …» подає як ранжування те, що ранжуванням не є, і моделі дає
                # хибний сигнал переваги першого. Ярус ріжеться за розривом балу.
                мах = усі[0]["бал"]
                ярус = [k for k in усі if k["бал"] >= мах - 0.03][:6]
                решта = len(усі) - len(ярус)
                частини = ", ".join(k["крій"] for k in ярус)
                хвіст = ("" if len(ярус) == 1 else " — рівносильні на цьому тілі")
                Р.append(_ребро(
                    f"крій_{слот}", [слот, "плечі" if слот == "верх" else "стегна"],
                    min(1.0, мах), "soft",
                    f"Крій {слота_родовий(слот)}: {частини}{хвіст} (бал {мах:.2f})."
                    + (f" Решта {решта} {_множина(решта, 'крій', 'крої', 'кроїв')} "
                       f"слабші, але не заборонені." if решта else ""),
                    f"бал = влучання × (1−напруга форми) × (1−напруга краю), "
                    f"оцінено {пр.get('оцінено')} комбінацій; ярус — за розривом 0.03",
                    інверсія=(f"Крій {слота_родовий(слот)} бери будь-який — на цьому тілі "
                              f"крій лінію не міняє."),
                    джерело="гіперграф.простір"))
            elif якщо_нема:
                # ── ГІЛКА БУЛА МЕРТВА ЗА ПОБУДОВОЮ (08.09.2026) ──────────────
                # Тут стояв порожній `рядок`, а останній рядок функції —
                # `return [р for р in Р if р["рядок"]]`. Отже ребро будувалось і
                # тут-таки відсіювалось: єдине повідомлення «жоден крій не дав
                # додатного балу» не доходило НІКУДИ. Це рівно той сигнал «входу
                # нема / усе заблоковано», заради якого модуль і писався проти
                # порожнього простору.
                # ДРУГА СМЕРТЬ І ДРУГЕ СЛОВО (10.09.2026). Рядок ожив, але лишався
                # недосяжним: `якщо_нема` брався з `крої`, порожніх рівно тоді, коли
                # ця гілка й потрібна. І текст був неправдивий: «простір закрито
                # блокером» — блокерів у силуеті нема взагалі (РЕГІСТР_ПРАВИЛА дає
                # лише «репліка»/«питання»), а найчастіша причина порожнечі — нульове
                # влучання. Тому причина тепер НЕ вгадується, а цитується з
                # `простір.порожньо`, який її знає.
                Р.append(_ребро(
                    f"крій_{слот}", [слот], 0.0, "питання",
                    f"Крій {слота_родовий(слот)}: жоден варіант не дав додатного балу "
                    f"на цьому тілі. Причина: {пр.get('порожньо')}. "
                    f"Найближчі за рангом: {', '.join(якщо_нема)}.",
                    f"ранг по ВСІХ оцінених комбінаціях ({пр.get('оцінено')}), "
                    f"жодна з них не дала додатного балу",
                    джерело="гіперграф.простір"))
    return [р for р in Р if р["рядок"]]


def слота_родовий(x):
    """Родовий відмінок імені слота для рядків брифа.

    ТУТ СТОЯЛО ТРИ ТОТОЖНІ ФУНКЦІЇ. `вужчому`, `ширшому` і `слота_родовий` мали
    байт у байт одне тіло: `{"верх": "верху", "низ": "низу"}.get(x, x)`. Три
    імені на одну відміну — і кожне наступне поповнення таблиці довелося б
    писати тричі, а розійшлися б вони мовчки.
    """
    return {"верх": "верху", "низ": "низу"}.get(x, x)


def інцидентність(ребра_):
    """Скільки ребер і скільки сумарної напруги несе кожен вузол.

    Це те, чого плаский список правил не дає в принципі: вузол, крізь який
    проходить чотири ребра, — місце, де правила конкурують, і саме його треба
    назвати моделі окремо. Напруга додається (а не множиться, як у `напруга`):
    тут питання не «наскільки погано», а «наскільки завантажений вузол».
    """
    в = {}
    for р in ребра_:
        for u in р["вузли"]:
            з = в.setdefault(u, dict(вузол=u, ребер=0, напруга=0.0, ребра=[]))
            з["ребер"] += 1
            з["напруга"] += р["напруга"]
            з["ребра"].append(р["ід"])
    for з in в.values():
        з["напруга"] = round(з["напруга"], 3)
    return sorted(в.values(), key=lambda з: (-з["напруга"], -з["ребер"]))


ЗОНИ_ТІЛА = ("плечі", "груди", "талія", "високе_стегно", "стегна",
             "коліно", "литка", "щиколотка")


def _множина(n, одн, дв, багато):
    """Українська узгодженість числівника. Дрібниця, але «5 умови» в брифі
    читається як недбалість, а недбалий бриф суддя оцінює як недбалу систему."""
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return одн
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return дв
    return багато


def вузол_напруги(ребра_, скільки=2):
    """Рядок брифа про найзавантаженіші вузли. Це і є місце стику код↔ші:
    код каже, ДЕ вузько; розв'язує вузол — модель.

    БЕРУТЬСЯ ТІЛЬКИ ЗОНИ ТІЛА, не слоти. Виміряно на першому ж прогоні: слоти
    «верх» і «низ» входять майже в кожне ребро, тож інцидентність за ними
    видавала «верх — 5 умов; низ — 5 умов» на будь-якому тілі. Величина, яка
    всім видає одну відповідь, не міряє нічого (та сама помилка, яку
    `силует.літера` вже проходив із «V» на кожному образі). Зона тіла має
    справжній розкид, бо ребра прив'язані до РІЗНИХ ландмарків.
    """
    інц = [з for з in інцидентність(ребра_)
           if з["вузол"] in ЗОНИ_ТІЛА and з["ребер"] >= 2 and з["напруга"] >= 0.5]
    if not інц:
        return None
    топ = інц[:скільки]
    # ── ЩО ЦЕ МІНЯЄ (правило «вузол», before/after, 08.09.2026) ───────────────
    # Обидва рядки зняті прогоном шляхом брифа (`бриф.py` знімає ВИМКНЕНІ_КОДИ
    # ДО цього виклику), тіло 168 / 98-92-72-100:
    # before: «ВУЗОЛ. Найбільше умов сходиться на одному місці тіла: «плечі»
    #          (баланс_пари, одна_лінія, крій_верх); «стегна» (баланс_пари,
    #          одна_лінія, крій_низ) — 3 умови. Розвʼязуй їх РАЗОМ однією
    #          річчю, а не кожну окремо: виконання однієї тут ламає сусідню.»
    # after:  «ВУЗОЛ. Найбільше умов сходиться на цих місцях тіла: «плечі»
    #          (3 умови); «стегна» (3 умови). Через обидві зони йдуть
    #          баланс_пари, одна_лінія — бери під них ОДНУ річ на обидві зони,
    #          бо виконана на «плечі» зрушує сусідню. Решта на «плечі»
    #          (крій_верх) сусідньої зони не чіпає — її правь окремо.»
    # Старий рядок недієвий: він вивалював обидва списки цілими й не казав, ЯКІ
    # саме умови ходять через ОБИДВІ зони, — а «разом однією річчю» розвʼязні
    # тільки вони; крій_верх сидить на плечах сам і другої зони не чіпає, тож
    # вимога брати його тією ж річчю — вигадана. До того ж «— 3 умови» бралося
    # з першого вузла, а стояло після переліку двох і читалось як число для
    # обох (на іншому тілі там 5 і 4).
    # Спільне й власне вже лежать у `з["ребра"]` обох вузлів: це розкладка
    # наявних імен, без жодного нового виміру, порога чи виклику.
    # ── РЕВІЗІЯ 08.09.2026: «сидить на одній зоні» → «сусідньої зони не чіпає»
    # Хвіст казав про власні умови головного вузла, що вони «сидять на одній
    # зоні». Скільки зон несе ребро — це `р["вузли"]`, а сюди приходить уже
    # `інцидентність`, де вузлів ребра нема: функція цього не міряє й міряти
    # не може. Порахувати вона вміє одне — що ребра нема в СУСІДА по топу, і
    # рівно це тепер і сказано. Що це не стилістика, видно на сирому вході
    # (без зняття ВИМКНЕНІ_КОДИ, те саме тіло 168 / 98-92-72-100):
    #   було: «Решта на «стегна» (баланс_пари, крій_низ) сидить на одній зоні»
    #   а баланс_пари стоїть на трьох зонах — плечі, груди, стегна.
    # На шляху брифа хиба не виходила назовні лише тому, що бриф знімає два
    # ребра ДО виклику; це властивість споживача, а не цієї функції.
    головна = топ[0]
    сусіди = топ[1:]
    спільні = [ід for ід in головна["ребра"]
               if any(ід in з["ребра"] for з in сусіди)]
    власні = [ід for ід in головна["ребра"] if ід not in спільні]
    ч = "; ".join(f"«{з['вузол']}» ({з['ребер']} "
                  f"{_множина(з['ребер'], 'умова', 'умови', 'умов')})" for з in топ)
    if спільні:
        return (f"ВУЗОЛ. Найбільше умов сходиться на цих місцях тіла: {ч}. "
                f"Через обидві зони йдуть "
                f"{', '.join(спільні)} — бери під них ОДНУ річ на обидві зони, бо "
                f"виконана на «{головна['вузол']}» зрушує сусідню."
                + (f" Решта на «{головна['вузол']}» ({', '.join(власні)}) сусідньої "
                   f"зони не чіпає — її правь окремо." if власні else ""))
    n = головна["ребер"]
    return (f"ВУЗОЛ. Усі умови сходяться на «{головна['вузол']}» одній: {n} "
            f"{_множина(n, 'умова', 'умови', 'умов')} — {', '.join(головна['ребра'])}. "
            f"Розводити нема куди: одна річ на цю зону мусить закрити всі.")


