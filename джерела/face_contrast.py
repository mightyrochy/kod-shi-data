# ── Ваги сил із корпусу. strong проти soft — це і є асиметрія K-CLR-02.
# Числа беруться з тієї самої шкали, що вже стоїть у `основи.ВАГА_СИЛИ`:
# strong 0.60, soft 0.25. Відношення 2.4 : 1 — не вигадане, а те, яким
# кодова база вже міряє різницю між цими двома регістрами.
ШТРАФ_ПЕРЕВИЩЕННЯ = 0.60      # [C·strong]
ШТРАФ_НЕДОБОРУ = 0.25         # [C·soft]

# K-CLR-04 [H]: волосся важить найбільше в сумарній оцінці value.
ВАГА_ВОЛОССЯ = 0.75

# K-CLR-03: помітний макіяж піднімає доступний контраст біля обличчя на крок.
# «Крок» тут — один крок Манселл-Value ≈ 10 L*.
ВАЖІЛЬ_МАКІЯЖУ_L = 10.0

# Масштаб насичення штрафу: два кроки Value.
МАСШТАБ_L = 20.0


def value_обличчя(F):
    """Світлота зони обличчя за K-CLR-04: волосся домінує.

    Не середнє по всьому — саме зважене, бо волосся зчитується першим і
    займає більшу площу навколо обличчя.
    """
    шк = (F.get("шкіра") or {}).get("L")
    вол = [v.get("L") for k, v in (F or {}).items()
           if k.startswith("волосся") and isinstance(v, dict) and v.get("L") is not None]
    if not вол and шк is None:
        return None
    if not вол:
        return float(шк)
    Lв = sum(вол) / len(вол)
    if шк is None:
        return float(Lв)
    return ВАГА_ВОЛОССЯ * Lв + (1.0 - ВАГА_ВОЛОССЯ) * float(шк)


def важіль_макіяжу(макіяж, L_обличчя):
    """Скільки L* контрасту помітний макіяж реально додає біля обличчя.

    БУЛО: пласкі +10 L* за сам факт макіяжу. ВАЖІЛЬ_МАКІЯЖУ_L = 10.0 — константа
    T3, фольклорна: «один крок Манселл-Value ≈ 10 L*». Вона не міряла нічого —
    нюдова помада на світлій шкірі й темна винна давали ту саму надбавку.

    СТАЛО: якщо колір макіяжу відомий, важіль — це ВИМІР |ΔL*| між найтемнішою
    (або найсвітлішою — береться більший модуль) зоною макіяжу й світлотою зони
    обличчя. Це не нове правило: K-CLR-03 каже «помада додає крок контрасту», а
    крок контрасту в цій системі всюди міряється саме дельтою L*. Змінилось те,
    що крок тепер рахується, а не постулюється.

    Повертає (Δ L*, джерело). Коли кольору нема — падає назад на константу, і
    джерело це прямо каже, щоб «10.0» ніде не читалось як вимір.

    СТЕЛЯ — ОДИН КРОК, НЕ ДВА. K-CLR-03 дає помаді рівно «+1 крок контрасту».
    Отже вимір має право лише ПОКАЗАТИ, ЩО КРОКУ НЕМА (нюд на світлому обличчі
    дає ~0), і не має права видати більше, ніж дозволило правило: сила ≤
    верифікація. Перша версія цієї правки стелі не мала, і виміряно вийшло:
    нюдова помада #d9a89a на світлому колориті піднімала ліміт з 12.3 до 24.4 —
    тобто майже подвоювала весь контраст особи, і ряд «рекомендовані» ріс з 5
    основ до 9. Нюд не робить із людини висококонтрастну.

    ⚠ ДЕ ЛАМАЄТЬСЯ: сира дельта не зважена ПЛОЩЕЮ. Губи займають кілька
    відсотків обличчя, тіні менше; фізично внесок у зчитуваний контраст меншає з
    площею, і тут це не враховано. Через стелю в один крок завищення обмежене,
    але не зняте: темна помада однаково дає повний крок, хоч площею його не
    відпрацьовує. Зважування площею потребує зонного виміру з фото, якого шар не
    виробляє (той самий блокер, що в K-FIT-02/06)."""
    if not isinstance(макіяж, dict) or L_обличчя is None:
        return ВАЖІЛЬ_МАКІЯЖУ_L, "константа T3 (кольору макіяжу не задано)"
    дельти = []
    for зона, hexx in макіяж.items():
        if not isinstance(hexx, str) or not hexx.strip().startswith("#"):
            continue
        from colorspace import hx as _hx
        дельти.append((abs(_hx(hexx)[0] - float(L_обличчя)), зона))
    if not дельти:
        return ВАЖІЛЬ_МАКІЯЖУ_L, "константа T3 (кольору макіяжу не задано)"
    д, зона = max(дельти)
    д = min(д, ВАЖІЛЬ_МАКІЯЖУ_L)
    return round(д, 1), "вимір: |ΔL*| «%s» до зони обличчя" % зона


def дозволений_контраст(контраст, макіяж=None, L_обличчя=None):
    """Скільки L* образ має право покласти біля обличчя.

    Береться `value_gap` особи; якщо на цей вихід заявлено помітний макіяж —
    плюс крок (K-CLR-03). Повертає (ліміт, чи_був_важіль).
    """
    g = (контраст or {}).get("value_gap")
    g = 0.0 if g is None else abs(float(g))
    є = bool(макіяж) and (isinstance(макіяж, dict) or
                          str(макіяж) not in ("немає", "none", "без макіяжу", ""))
    if not є:
        return g, False
    д, джерело = важіль_макіяжу(макіяж, L_обличчя)
    return g + д, dict(Δ=д, джерело=джерело)


def бал_контрасту(L_кольору, L_обличчя, ліміт):
    """K-CLR-02 у неперервному вигляді. 1.0 — рівно в контрасті особи.

    Перевищення карається у 2.4 раза сильніше за недобір — це і є асиметрія.
    Ніякого порогу: обидві гілки — рампи.
    """
    факт = abs(float(L_кольору) - float(L_обличчя))
    надл = факт - ліміт
    коеф = ШТРАФ_ПЕРЕВИЩЕННЯ if надл > 0 else ШТРАФ_НЕДОБОРУ
    штраф = коеф * min(1.0, abs(надл) / МАСШТАБ_L)
    напрям = ("перевищує" if надл > 1.0 else "недобирає" if надл < -1.0 else "в міру")
    return max(0.0, 1.0 - штраф), факт, напрям


def домінантність(F, надійність_хроми=0.35):
    """value-домінантна / colour-домінантна / збалансована.

    Corpus [C·strong]: colour-домінантна з низьким value contrast вицвітає в
    самих нейтралах — їй треба справжні кольори на близьких value.
    Рахується з хроми рис; сила висновку обмежена зверху надійністю хроми.
    """
    C = [v.get("C") for k, v in (F or {}).items()
         if isinstance(v, dict) and v.get("C") is not None
         and (k == "шкіра" or k.startswith("волосся") or k == "очі")]
    if not C:
        return dict(рід="невідомо", сила=0.0, власна_хрома=None)
    хрома = sum(C) / len(C)
    # 20 C* — межа, за якою «власні барви помітні». T3: число з практики,
    # калібрувати на золотому наборі разом із ЦІЛЬ_ХРОМИ.
    сила = max(0.0, min(1.0, (хрома - 20.0) / 15.0)) * надійність_хроми
    return dict(рід=("colour" if хрома >= 20.0 else "value"),
                сила=round(сила, 3), власна_хрома=round(хрома, 1))


def штраф_нейтралі(дом, рівень_контрасту):
    """Скільки знімати з чистої нейтралі для colour-домінантної особи.

    Спрацьовує лише на перетині двох умов, як і в корпусі: colour-домінантна
    І низький value contrast. На висококонтрастній або value-домінантній
    нейтраль не карається взагалі.
    """
    if дом.get("рід") != "colour" or рівень_контрасту != "низький":
        return 0.0, None
    return дом["сила"], ("власні барви помітні, а перепад світлоти малий: "
                         "у самих нейтралах такий тип вицвітає (K-CLR-02, "
                         "домінантність [C·strong])")
