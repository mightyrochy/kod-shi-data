def _вага_полотна(р):
    """(слово, вага, поле) полотна речі. (None, None, None) — слово мовчить.

    ПОРЯДОК ПОЛІВ — ЦЕ ПОРЯДОК ДОВІРИ, а не зручності: рід із назви говорить про
    конструкцію й майже завжди мовчить про вагу, тому першим стоїть він і його
    мовчання одразу пускає далі, до складу магазина й до латинського роду.
    ЗНАЧЕННЯ, ЯКІ ПРО ВАГУ МОВЧАТЬ (`ПРО_ВАГУ_МОВЧАТЬ`), відсіюються ДО пошуку
    ключа: інакше «поліестер» ловився б підрядком «естер»… ні, гірше — «полотно»
    не ловилось би нічим і мовчало б тихо, тобто невідрізняльно від речі, у якої
    поля нема зовсім. Різниця між «слово є й воно про вагу не каже» і «слова нема»
    лишається видимою в полі, яке функція повертає третім.
    """
    for поле in ПОЛЯ_ПОЛОТНА:
        слово = str(р.get(поле) or "").lower().strip()
        if not слово or any(м in слово for м in ПРО_ВАГУ_МОВЧАТЬ):
            continue
        збіг = [(k, v) for k, v in ТКАНИНА_ВАГА.items() if k in слово]
        if збіг:
            k, v = max(збіг, key=lambda kv: len(kv[0]))   # найдовший корінь виграє
            return слово, v, поле
    return None, None, None


