def вартість_носіння(речі, тривалість_год=None, поверхня=None):
    """K-END-01 (вісь) + K-SHO-16 (каблук) + K-END-02 (мова відмови).

    ЩО ЦЕ МІНЯЄ (before/after). before — система оптимізує вигляд і не звітує про
    зручність ніде; гарний неносибельний образ має ТУ САМУ оцінку, що носибельний, і
    збирає «ні» від тестувальниці без жодного пояснення, яке система вміє прочитати.
    after — сценарій несе ТРИВАЛІСТЬ і ПОВЕРХНЮ, кандидати оцінюються проти них, і
    вердикт «ні» стає читабельним: система відрізняє «не подобається» від «муляє».

    ДЕ ЛАМАЄТЬСЯ: тривалості й поверхні нема в жодному фіді й нема в анкеті. Це
    властивості НАГОДИ, які діалоговий шар уже витягає, — тобто вхід є питанням, не
    даними. І весь доказ зібраний на БЛОЧНОМУ каблуці: шпилька, танкетка й платформа в
    ньому не розділені, а висота платформи компенсує кут стопи так, як жодне з цих
    досліджень не міряло.
    """
    зн = []
    if тривалість_год is None and поверхня is None:
        for р in речі:
            сл = р.get("слот")
            if сл in НЕСТЕРПНІСТЬ:
                _СЛ.запис("K-END-01", "вартість носіння не рахована: нема сценарію",
                          "вартість_носіння", значення=сл, сила=0.0, напрям="вхід — питання")
        if any(р.get("слот") in НЕСТЕРПНІСТЬ for р in речі):
            зн.append(dict(_зн("K-END-01", "питання",
                "вартість носіння не рахована: сценарій не несе тривалості й поверхні",
                sorted({р.get("назва") or р.get("id") for р in речі
                        if р.get("слот") in НЕСТЕРПНІСТЬ}),
                "носибельність — вісь нарівні з посадкою й когерентністю, а не застереження; "
                "це найбільше передбачене джерело вердиктів «не носитиму», і без тривалості "
                "й поверхні такі вердикти неінтерпретовні: невідомо, відмова естетична чи фізична",
                ремонт="два питання діалогу: скільки годин і по чому ходити",
                ламається="тривалість і поверхня — властивості нагоди, не даних; діалоговий "
                          "шар їх уже витягає, тож вхід є питанням, а не полем фіду"),
                сила_нп=0.0, сила_нп_джерело="входу нема (тривалість і поверхня)"))
        return зн
    коеф = ПОВЕРХНІ.get((поверхня or "").lower(), 1.0)
    год = float(тривалість_год or 1.0)
    нестерпні = []
    for р in речі:
        сл = р.get("слот")
        назва = р.get("назва") or р.get("id") or "річ"
        if сл == "взуття":
            каблук = р.get("каблук_см")
            if каблук is None:
                if р.get("каблук") is True:
                    зн.append(dict(_зн("K-SHO-16", "питання",
                        "каблук є, висоти нема", [назва],
                        "категорія каже «на підборах» і не каже скільки; вартість носіння без "
                        "висоти не рахується",
                        ремонт="висота каблука зі специфікації товару",
                        ламається="українські картки дають висоту нерегулярно"),
                        сила_нп=0.0, сила_нп_джерело="входу нема (висота каблука)"))
                continue
            h = float(каблук)
            # НЕПЕРЕРВНА вартість, не поріг. Нуль до 4 см; зростає по смузі 4–7;
            # плюс надбавка в смузі найбільших скарг 6–9; множиться на години й поверхню.
            база = max(0.0, (h - C["каблук_смуга_низ"]) / max(1e-6, C["каблук_смуга_верх"] - C["каблук_смуга_низ"]))
            скарги = 1.0 if C["каблук_скарги_низ"] <= h <= C["каблук_скарги_верх"] else 0.0
            вартість = round(min(1.0, (база + 0.35 * скарги) * min(2.0, год / 4.0) * коеф), 2)
            if вартість < 0.12:
                continue
            зн.append(dict(_зн("K-SHO-16", "soft" if вартість >= 0.5 else "hint",
                "каблук %.1f см на %.0f год по %s" % (h, год, поверхня or "невідомій поверхні"),
                [назва],
                "смуга комфорту з багатодослідницького консенсусу — 4–7 см; смуга найбільших "
                "скарг — 6–9 см (55%% із 200 жінок, що носять регулярно, самозвіт); "
                "енергетична вартість пересування в каблуку підвищена, і це прямий механізм "
                "«я не витримаю тут вісім годин»",
                ремонт=["це НЕ вето: вартість названа, вибір ваш",
                        "якщо день стоячий — пара нижче 4 см знімає її повністю",
                        "контактна устілка з пʼятковою чашею й підтримкою склепіння знижує "
                        "ударне навантаження на 33 %% — та сама пара стає іншим обʼєктом"],
                ламається="увесь доказ на БЛОЧНОМУ каблуці: шпилька, танкетка й платформа не "
                          "розділені, а висота платформи компенсує ефективний кут так, як "
                          "жодне з досліджень не міряло. Вікова смуга вузька (двадцятиліття). "
                          "І «−1° поперекового згину на +1 см» — n = 5, пілотний масштаб",
                поріг=C["каблук_смуга_низ"], вимір=h),
                сила_нп=вартість,
                сила_нп_джерело="вимір (висота × тривалість × коефіцієнт поверхні)"))
            _СЛ.запис("K-SHO-16", "вартість носіння каблука названа", "вартість_носіння",
                      значення="%.1f см / %.0f год / %s" % (h, год, поверхня), сила=вартість,
                      напрям="названа вартість, не вето")
        elif сл in НЕСТЕРПНІСТЬ and год >= 6:
            нестерпні.append((сл, назва))
        continue
    # ── ОДИН РЯДОК НА ОБРАЗ, БО ІНАКШЕ ЗЛИТТЯ З'ЇДАЄ ВЕСЬ ЗМІСТ ПРАВИЛА ──────
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after, виміряно 17.09.2026 на живому шляху,
    # `bridge.від_моделі`, сценарій із `тривалість_год=9`).
    # Емітент віддавав ОКРЕМУ знахідку на кожну нестерпну річ, і це було правильно
    # рівно доти, доки їх не стало більше однієї. Далі по дорозі стоїть
    # `pipeline.знахідки_вердикту` з правилом Н-P37 «ОДНЕ ПРАВИЛО — ОДИН РЯДОК»:
    # знахідки з тим самим `правило` зливаються в одну з найбільшою силою, речі
    # обʼєднуються, а суть береться від НАЙСИЛЬНІШОЇ. Наслідок точний:
    #   before — суть «„Сумка жіноча Phoenix“ на довгий день — вага на одному плечі;
    #            вузький ремінь ріже; ремінь сповзає (+2 за цим самим правилом)»,
    #            речі [сумка, блуза з шарфом, екошуба]. Механізм шарфа («сповзає й
    #            потребує постійного поправляння») і механізм верхнього шару («у
    #            приміщенні треба зняти, а подіти нікуди») ЗНИКАЛИ, і жінка діставала
    #            механізм сумки, приписаний трьом речам.
    #   after  — один рядок називає КОЖНУ річ із ЇЇ механізмом, зливати нема чого,
    #            і таблиця `НЕСТЕРПНІСТЬ` — тобто єдиний зміст правила — доїжджає
    #            цілою.
    # ЧОМУ НЕ ПРАВИТИ ЗЛИТТЯ: воно загальне й правильне — три знахідки одного
    # правила про три речі з ОДНАКОВИМ текстом мусять бути одним рядком. Тут же
    # тексти РІЗНІ за побудовою, і це властивість K-END-02, а не труби. Дубль кодів
    # лікується там, де знахідка НАРОДЖУЄТЬСЯ (Н-V15-035) — тут і лікується.
    if нестерпні:
        _ім = lambda н: (н or "річ")[:34]
        рядки = ["«%s» — %s" % (_ім(назва), НЕСТЕРПНІСТЬ[сл]) for сл, назва in нестерпні]
        зн.append(dict(_зн("K-END-02", "hint",
            "на довгий день (%.0f год) кожна з цих речей стає нестерпною по-своєму: %s"
            % (год, " · ".join(рядки)),
            [назва for _, назва in нестерпні],
            "спільний знаменник усіх таких відмов один: річ, яка вимагає уваги під час "
            "носіння, дістане «ні» незалежно від вигляду. Механізми різні, і саме "
            "різниця тут і є змістом: вона відрізняє «не подобається» від «муляє»",
            ремонт=None,
            ламається="жодна з цих причин не має ані порога, ані входу у фіді. Це МОВА "
                      "ДЛЯ ДІАЛОГУ, не фільтр — і це нормально, канал 3 працює саме так. "
                      "Поріг 6 годин — межа, за якою скарги практиків починаються, а не "
                      "виміряна точка зламу",
            поріг=6.0, вимір=год, повна=6.0),
            сила_нп=round(min(0.5, (год - 6.0) / 12.0 + 0.2), 2),
            сила_нп_джерело="категорія (перелік фізичних причин відмови) × тривалість"))
    if зн:
        _СЛ.запис("K-END-01", "носибельність як вісь першого класу", "вартість_носіння",
                  значення="%.0f год × %s" % (год, поверхня or "?"), сила=None,
                  напрям="вартість названа людині")
    return зн
