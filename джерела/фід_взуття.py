# ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after). Аудит контрактів показав це прямо, щойно
# перестав сканувати половину коду: `accessory` читав `виріз_стопи`, `халява_рівень`,
# `каблук_см`, `матеріал_верху`, `підошва` — і НІХТО їх не писав. Правило, що читає
# поле, якого ніхто не пише, мовчить завжди й не лишає сліду про те, що мовчить: це
# рівно той антипатерн «вимір над заглушкою», який система вже ловить деінде.
# Тепер вони ВИВОДЯТЬСЯ тим самим механізмом, що слот і тип — із категорії й назви.
#
# ЧОГО ТУТ НЕМА НАВМИСНО:
#   · ВИСОТА ХАЛЯВИ В САНТИМЕТРАХ. Фід її не несе, а «щиколотка / литка / коліно» —
#     це РІВНІ ТІЛА, різні на різних зростах. Тому тут віддається лише РІВЕНЬ
#     (порядкова мітка), а в сантиметри його переводить accessory на профілі
#     КОНКРЕТНОЇ людини. Ярлик лишається маршрутизацією, як велить корпус.
#   · ФОРМА НОСКА (K-SHO-12): поля нема, з назви не витягається, величина зсуву
#     формальності невідома. Лишається в accessory.БЕЗ_ВХОДУ.
# ⚠ ОСНОВИ, НЕ ПОВНІ СЛОВА. Перша версія писала «замша», «шкіра», «устілці»,
# «шпильк» — і проба показала, що вона пропускає «замшеві», «устілка», «шпильці»,
# «на підборах 7 см». Це той самий клас помилки, що вже спіймався в language_gate
# («виглядатимете дешево» повз патерн без \w*): патерн, писаний під власний
# приклад, ловить власний приклад. Порядок значущий — «екошкір» перед «шкір».
# ⚠ ДВА РЕГЕКСИ НА УСТІЛКУ, І ЦЕ ВИМІР, А НЕ СМАК (11.09.2026, наряд Н-V13-026).
# ЩО БУЛО. Одинична регулярка брала ПЕРШЕ двоцифрове число після слова «устілк».
# А український роздріб пише не число, а РОЗМІРНУ ТАБЛИЦЮ: «розмір довжина
# устілки 36 22,7 см 37 23,5 см 38 24 см …». Отже ловився ЄВРОРОЗМІР.
# ВИМІРЯНО НА `каталог_повний` (10 770 оферів, 2 096 взуття, 191 опис зі словом
# «устілк»): `устілка_см` писалась 59 разів, УСІ 59 — рівно 36.0. Проти стопи
# 245 мм це «припуск +115 мм», тобто K-SHO-15 на кожній такій парі — ХИБНИЙ
# ВИМІР там, де чесна відповідь «не названо». Це рівно той клас помилки, який
# коментар до `МАТЕРІАЛИ_ВЕРХУ` нижче вже документує: патерн, писаний під
# власний приклад, ловить власний приклад.
# ЩО СТАЛО. Таблиця РОЗПІЗНАЄТЬСЯ й ГЛУШИТЬ одиничне читання (число в ній
# належить конкретному розміру, а обраного розміру пари система ніде не тримає),
# а одиничне число пишеться лише в межах фізично можливої внутрішньої довжини
# жіночого взуття. Тоді ворота виходять ПИТАННЯМ («поле речі «устілка_см»»), а
# не хибним виміром — та сама різниця, яку декларує докстрінг `взуттєві_атрибути`
# («None означає «не названо», НЕ «нема»»).
# ЧОМУ ТАБЛИЦЯ НЕ ПИШЕТЬСЯ В ПОЛЕ. Читач їй потрібен один — «устілка обраного
# розміру», — а обраного розміру пари не тримає ЖОДЕН шар. Поле без читача
# заборонене (§4 п.12 СТАНДАРТ_КОДУ.md), і наряд називає цей крок окремим
# рішенням власника. Дані з опису нікуди не зникають: щойно розмір пари
# з'явиться, та сама регулярка віддасть таблицю.
# ЧОМУ ЦІЛІ САНТИМЕТРИ ТЕЖ (відхилення від букви наряду, на виміряній підставі):
# форма наряду `(2[0-9][.,]\d|3[0-3][.,]\d)` вимагає десяткової коми й мовчки
# губить рядок «38 24 см» у таблиці, де решта рядків із комою. Прогін по всіх
# 191 описах: обидві форми спрацьовують на тих самих 59 парах і ЖОДНОГО разу
# поза ними (0 хибних на 2 096 взуття), але форма з необов'язковою комою бере
# таблицю ЦІЛКОМ, а не 5 рядків із 6.
# Фізично можлива внутрішня довжина жіночого взуття, см. Межі — область
# визначення виміру, не поріг рішення: за ними число не є довжиною устілки.


З_КАБЛУКОМ = ("на підбор", "на каблук", "на подбор", "шпильц", "шпильк", "танкетц",
               "танкетк", "платформ")



def число_см(v):
    """Число з param жниварки («4», «1.5», «22,5») або None. Порожнє й нечислове —
    None, а не 0: нуль тут означав би «каблука нема», і це вердикт, не мовчання."""
    if v in (None, ""):
        return None
    try:
        return float(str(v).strip().replace(",", "."))
    except (TypeError, ValueError):
        return None


# ── КЛАС ВИСОТИ — НЕ ВИСОТА (рядок 196, 24.09.2026) ─────────────────────────
# Крамниця може писати у поле висоти не сантиметри, а СМУГУ свого фільтра: «до 4 см
# (або без підборів)», «від 4 до 6 см», «більше 6 см». Розбирач брав звідти число —
# і воно ставало «висотою». Виміряно на `каталог_повний` (343 пари attico.ua): усі
# 341 з висотою мали рівно два значення, 4 і 6, і «4» стояло на 46 кросівках, 15
# балетках, 15 кедах, 15 лоферах. Сторінки самої крамниці (18 пар, по 6 на клас)
# кажуть, чим ці числа були насправді:
#   «до 4 см (або без підборів)» → 1,5 · 1,5 · 1,5 · 3 · 3,5 · 4
#   «від 4 до 6 см»              → 5 · 5 · 5 · 6 · 6 · 6,5
#   «більше 6 см»                → 7,5 · 9,5 · 9,5 · 9,5 · 10,5 · 10,5
# Тобто число у фіді — ВЕРХНІЙ КРАЙ смуги, а два різні класи («4–6» і «>6») злиті
# в одну шістку: каблук 10,5 см їхав у код як 6.
# ТОМУ: смуга лишається смугою. Висоти, якої крамниця не дала, не вигадуємо —
# `каблук_см` тут не ставиться взагалі, і далі вирішує тип пари (рядок 181,
# `міст_відповіді._низька`: «висота, коли вона є, сильніша за тип»).
# ІМЕНІ КРАМНИЦІ В КОДІ НЕМА: розпізнаємо формулювання, а не магазин, — інакше
# наступна крамниця з тим самим фільтром знову їхала б числом.
_СМУГА_ДО = re.compile(r"(?i)\bдо\s+(\d+(?:[.,]\d+)?)\s*см")
_СМУГА_ВІД_ДО = re.compile(r"(?i)\bвід\s+(\d+(?:[.,]\d+)?)\s*(?:см)?\s*до\s+(\d+(?:[.,]\d+)?)\s*см")
_СМУГА_ПОНАД = re.compile(r"(?i)\b(?:більше|понад|від)\s+(\d+(?:[.,]\d+)?)\s*см")


def _чис(x):
    return float(str(x).replace(",", "."))


def смуга_каблука(текст):
    """(від, до, слова) для формулювання-СМУГИ, або None для числа чи мовчання.

    `від` = None означає «нижнього краю крамниця не назвала» (смуга «до 4» включає
    і пару без каблука), `до` = None — «верхнього нема» («більше 6»). Порядок
    розбору важить: «від 4 до 6» мусить прочитатись раніше за «до 6» і за «від 4».
    """
    т = (текст or "").strip()
    if not т:
        return None
    м = _СМУГА_ВІД_ДО.search(т)
    if м:
        return (_чис(м.group(1)), _чис(м.group(2)), т)
    м = _СМУГА_ДО.search(т)
    if м:
        return (None, _чис(м.group(1)), т)
    м = _СМУГА_ПОНАД.search(т)
    if м:
        return (_чис(м.group(1)), None, т)
    return None


def _смуга_з_параметрів(пар):
    """Смуга з СИРОГО поля крамниці про підбори (`~…`), якщо вона там смуга."""
    for ім, зн in (пар or {}).items():
        н = str(ім).lower()
        if not н.startswith("~"):
            continue
        if not ("підбор" in н or "каблук" in н):
            continue
        с = смуга_каблука(зн)
        if с:
            return с
    return None


# ── ВИСОТА, ЯКУ ЖНИВАРКА НЕ ЗВЕЛА В `каблук_см` (рядок 196, 24.09.2026) ─────
# Знайдено приймальним проходом тестувальниці: на сіді 7 в офіс із «без підборів»
# рука 1 дістала туфлі theoriginals на 13 см. Поле з висотою в них Є — крамниця
# пише `Висота підбора` = 13, — але це ім'я жниварка в `каблук_см` не зводить, і
# код не знав про пару НІЧОГО: ні висоти для стелі (K-PER-00), ні `каблук` для
# сенсорного вето (`profile.СЕНСОРНІ`), яке саме цю пару й мусило зняти.
# ВИМІРЯНО НА `каталог_повний`: таких пар 135 — theoriginals 112, welfare 23; у
# жодної з них `каблук_см` нема (0 із 135), значення від 1 до 15.
# ОДИНИЦІ — САНТИМЕТРИ, І ЦЕ НЕ ЗДОГАД (свідки, як у рядку 178):
#   · сторінка welfare показує те саме число тим самим підписом («Висота підбора
#     8.5» на човниках Tamaris), тобто фід не перекручує поле картки;
#   · опис речі називає висоту словами в 6 парах — 5 збігаються з полем точно
#     («каблук 7 см» при 7), шоста різниться на 0,5 (округлення крамниці);
#   · порядок величин тримається типу: балетки 1, лофери 2–3, човники 5–11.
#   · theoriginals за Cloudflare і сторінкою не свідчить — тому число береться як
#     СЛОВО КРАМНИЦІ, рівно як `каблук_см` з будь-якого іншого фіду, не як вимір.
# ІМЕНІ КРАМНИЦІ В КОДІ НЕМА: впізнається формулювання поля, а не магазин.
# ЗНАЧЕННЯ МУСИТЬ БУТИ САМИМ ЧИСЛОМ («8», «6,5 см»): поле cooshwear
# «~Висота підборів - 5 см Довжина устілки» несе перелік устілок по розмірах —
# число там є, але воно не про підбори, і таке поле лишається непрочитаним.
_ІМ_ВИСОТИ = re.compile(r"(?i)висот\w*\s+(?:підбор|каблук|подбор)")
_ЛИШЕ_ЧИСЛО_СМ = re.compile(r"(?i)^(\d{1,3}(?:[.,]\d+)?)\s*(?:(см|мм)\.?)?$")
# ОДИНИЦЯ В НАЗВІ ПОЛЯ (рядок 1988): «Висота підбора, мм» + значення «35» — це 3,5 см, а не
# 35. Без цього число з міліметрового поля читалось би сантиметрами (або відкидалось
# стелею, або — при «8 мм» — ставало 8 см). Одиниця самого значення старша за поле.
_ММ_У_НАЗВІ_ПОЛЯ = re.compile(r"(?i)(?<![а-яіїєґa-z])мм(?![а-яіїєґa-z])")
# Стеля здорового глузду: найвище в каталозі — 15 см (туфлі на платформі). Число
# понад це не висота підбора, а помилка поля, і краще не знати, ніж знати хибно.
ВИСОТА_КАБЛУКА_МАКС_СМ = 20.0


def висота_з_параметрів(пар):
    """(число см, ім'я поля) з поля крамниці про висоту підбора, або None.

    Читається лише те, чого жниварка не звела в `каблук_см`, і лише коли значення
    поля — САМЕ ЧИСЛО («8», «6,5 см.»). Смуга («від 4 до 6 см») сюди не потрапляє:
    її окремо читає `_смуга_з_параметрів`, і висотою вона не стає.
    """
    for ім, зн in (пар or {}).items():
        н = str(ім).lstrip("~").strip()
        if not _ІМ_ВИСОТИ.search(н):
            continue
        м = _ЛИШЕ_ЧИСЛО_СМ.match(str(зн or "").strip())
        if not м:
            continue
        ч = число_см(м.group(1))
        одиниця = (м.group(2) or "").lower() or ("мм" if _ММ_У_НАЗВІ_ПОЛЯ.search(н) else "см")
        if ч is not None and одиниця == "мм":
            ч = ч / 10.0
        if ч is not None and 0.0 <= ч <= ВИСОТА_КАБЛУКА_МАКС_СМ:
            return (ч, ім)
    return None


# ПОВНОТА З ПОЛЯ КРАМНИЦІ (рядок 1988). Поле «повнота» є на 206 оферах каталогу, текстовий
# вираз `_ПРО_ПОВНОТУ` читав його лише з назви й опису (прочитано 47) — слово крамниці в самому
# полі лишалось повз. Читається ім'я поля («повнота», «~повнота:», «~повнота взуття») і
# основа слова в його значенні; два різні слова в одному значенні («G (середня), F (вузька)» —
# літери повноти по розмірах) не дають вибору — чесно «невідомо», без першого з двох.
# Значення поза трьома основами («Стандартне», «повнорозмірний») теж лишається непрочитаним:
# відповідності їм у `_ПОВНОТА_СЛОВО` нема, вигадувати її тут — не наша справа.
_ІМ_ПОВНОТИ = re.compile(r"(?i)^повнот")


def повнота_з_параметрів(пар):
    """«вузька» / «середня» / «широка» з поля крамниці про повноту, або None."""
    for ім, зн in (пар or {}).items():
        if not _ІМ_ПОВНОТИ.match(str(ім).lstrip("~ ").strip()):
            continue
        слова = {к for к in _ПОВНОТА_СЛОВО if к in str(зн or "").lower()}
        if len(слова) == 1:
            return _ПОВНОТА_СЛОВО[слова.pop()]
    return None


def висота_або_підлога(r):
    """Висота пари для питання «чи вона ВИЩА за стелю», у см, або None.

    Крамниця дала число — це воно. Дала смугу («більше 6 см») — це її НИЖНІЙ край:
    він доведений, пара точно не нижча. Смуга без нижнього краю («до 4 см (або без
    підборів)») нічого не доводить, і тут чесна відповідь — None.
    ДЛЯ ЗВОРОТНОГО ПИТАННЯ («чи вона НИЖЧА за поріг») ця функція не годиться: з
    «до 4» пара може бути і 4 см, і 0 — там вирішує тип (рядок 181).
    """
    h = r.get("каблук_см")
    if h is not None:
        try:
            return float(h)
        except (TypeError, ValueError):
            return None
    від = r.get("каблук_від")
    return None if від is None else float(від)


