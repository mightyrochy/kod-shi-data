# ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after). Аудит контрактів показав це прямо, щойно
# перестав сканувати половину коду: `accessory` читав `виріз_стопи`, `халява_рівень`,
# `каблук_см`, `матеріал_верху`, `підошва` — і НІХТО їх не писав. Правило, що читає
# поле, якого ніхто не пише, мовчить завжди й не лишає сліду про те, що мовчить: це
# рівно той антипатерн «вимір над заглушкою», який система вже ловить деінде.
# Тепер вони ВИВОДЯТЬСЯ з кодів: тип речі, число фіду, код моделі на фото (див. нижче).
#
# ЧОГО ТУТ НЕМА НАВМИСНО:
#   · ВИСОТА ХАЛЯВИ В САНТИМЕТРАХ. Фід її не несе, а «щиколотка / литка / коліно» —
#     це РІВНІ ТІЛА, різні на різних зростах. Тому тут віддається лише РІВЕНЬ
#     (порядкова мітка), а в сантиметри його переводить accessory на профілі
#     КОНКРЕТНОЇ людини. Ярлик лишається маршрутизацією, як велить корпус.
#   · ФОРМА НОСКА (K-SHO-12): поля нема, з назви не витягається, величина зсуву
#     формальності невідома. Лишається в accessory.БЕЗ_ВХОДУ.
ВИРІЗ_ЗА_ТИПОМ = {
 # low vamp: нога читається як така, що починається від пальців
 "човники": "низький", "туфлі": "низький", "балетки": "низький",
 "босоніжки": "низький", "сандалі": "низький", "мюлі": "низький",
 "еспадрильї": "низький",
 # халява висока, а сам виріз на стопі низький — це ДВІ НЕЗАЛЕЖНІ ОСІ, і тема
 # велить їх не змішувати: човник має низький виріз і низьку масу, чобіт до коліна —
 # низький виріз і високу масу
 "чоботи": "низький", "ботфорти": "низький",
 # high vamp: край лягає посеред стопи або на щиколотці
 "лофери": "високий", "мокасини": "високий", "черевики": "високий",
 "челсі": "високий", "кросівки": "високий", "кеди": "високий", "уггі": "високий",
}
ХАЛЯВА_ЗА_ТИПОМ = {
 "човники": None, "туфлі": None, "балетки": None, "лофери": None, "мокасини": None,
 "босоніжки": None, "сандалі": None, "мюлі": None, "еспадрильї": None,
 "кросівки": "щиколотка", "кеди": "щиколотка",
 "черевики": "щиколотка", "челсі": "щиколотка", "уггі": "литка",
 "чоботи": "коліно", "ботфорти": "пах",
}
# ЩО ЦЕ МІНЯЄ В РІШЕННІ (рядок 5192, п.12): код не читає слів. Колишні `МАТЕРІАЛИ_ВЕРХУ`,
# `ПІДОШВИ`, регулярки каблука й устілки та списки «на підборах / без підборів» шукали
# слова в категорії, назві й описі — це читання людських слів, і воно прибране. Властивість
# взуття тепер береться з кодів: матеріал верху — з коду моделі на фото (`матеріал_фото`,
# qwen верхнього рівня; `матеріал_верху_з_коду`), висота каблука й халяви — з числа фіду.
# Коду нема — поля нема: `None` у цьому файлі означає «невідомо», не «нема».
# Висота каблука: число `каблук_см` жниварки, але лише коли сирі поля висоти підбора тієї
# ж речі теж мають вигляд числа з коротким хвостом («9», «1,5 см.»). Фраза-фільтр крамниці
# («до 4 см (або без підборів)», «від 4 до 6 см») числом не є: жниварка кладе в `каблук_см`
# її край, і висотою він бути не може. Форма значення — не його смисл: слова код не розбирає.
ПОЛЯ_СИРОЇ_ВИСОТИ = ("~висота підборів", "~висота каблука", "~висота підбора",
                     "~висота підбору (37р.)")
ПОЛЕ_ПРЯМОЇ_ВИСОТИ = "висота підбора"
_ЧИСЛО_З_ХВОСТОМ = re.compile(r"^(\d+(?:[.,]\d+)?)\s?\D{0,3}$")
# Стеля здорового глузду: найвище в каталозі — 15 см (туфлі на платформі). Число
# понад це не висота підбора, а помилка поля, і краще не знати, ніж знати хибно.
ВИСОТА_КАБЛУКА_МАКС_СМ = 20.0


def _число_см(v):
    """Число з param жниварки («4», «1.5», «22,5») або None. Порожнє й нечислове —
    None, а не 0: нуль тут означав би «каблука нема», і це вердикт, не мовчання."""
    if v in (None, ""):
        return None
    try:
        return float(str(v).strip().replace(",", "."))
    except (TypeError, ValueError):
        return None


def висота_каблука_см(пар):
    """Висота каблука в см з числа фіду, або None («невідомо»). Нуль — відповідь крамниці
    «каблука нема», не мовчання. Сире поле висоти, що не має вигляду числа (фраза-фільтр
    крамниці), скасовує й зведене число: воно лише край її смуги."""
    пар = пар or {}
    for ім in ПОЛЯ_СИРОЇ_ВИСОТИ:
        if ім in пар and not _ЧИСЛО_З_ХВОСТОМ.match(str(пар[ім] or "").strip()):
            return None
    ч = _число_см(пар.get("каблук_см"))
    if ч is None:
        м = _ЧИСЛО_З_ХВОСТОМ.match(str(пар.get(ПОЛЕ_ПРЯМОЇ_ВИСОТИ) or "").strip())
        ч = _число_см(м.group(1)) if м else None
    return ч if ч is not None and 0.0 <= ч <= ВИСОТА_КАБЛУКА_МАКС_СМ else None


def висота_або_підлога(r):
    """Висота пари для питання «чи вона ВИЩА за стелю», у см, або None (не названо)."""
    h = r.get("каблук_см")
    if h is None:
        return None
    try:
        return float(h)
    except (TypeError, ValueError):
        return None


def матеріал_верху_з_коду(r):
    """Матеріал верху взуття — код моделі з фото (`матеріал_фото`, qwen верхнього рівня), як
    є; кладе його в `матеріал_верху` запису каталогу. Коду нема — поля нема (невідомо)."""
    if r.get("слот") == "взуття" and r.get("матеріал_фото"):
        r["матеріал_верху"] = r["матеріал_фото"]


def _взуттєві_поля(offer, тип=None):
    """Атрибути взуття: типові поля з коду типу, висота каблука й халяви — з чисел фіду.

    Один словник, не два сплати: `dict(**a, **b)` з тим самим ключем — TypeError."""
    a = dict(взуттєві_атрибути(offer, тип))
    пар = offer.get("параметри") or {}
    h = висота_каблука_см(пар)
    if h is not None:
        a["каблук_см"], a["каблук"] = h, h > 0
    халява = _число_см(пар.get("халява_см"))
    if халява is not None:
        a["халява_см"] = халява
    return a


def взуттєві_атрибути(offer, тип=None):
    """Атрибути взуття з коду типу речі. None означає «не названо», НЕ «нема»:
    різниця вирішальна, бо на None правило виходить питанням, а на False — вердиктом."""
    тип = тип or тип_речі(offer)
    a = dict(виріз_стопи=ВИРІЗ_ЗА_ТИПОМ.get(тип),
             халява_рівень=ХАЛЯВА_ЗА_ТИПОМ.get(тип, None),
             халява_джерело="тип" if тип in ХАЛЯВА_ЗА_ТИПОМ else None)
    return {k: v for k, v in a.items() if v is not None}
