def цілі_образів(H=None):
    return [ЦІЛЬ_ОБРАЗУ(ч) for ч, _ in НАВМИСНІ(H or {})]


def з_геометрією(речі, профіль):
    """Речі з ПОХОДЖЕННЯМ ПЛОЩІ — площа й `near` пораховані з оголошених см.

    ── ЧОМУ ПІВ БАТАРЕЇ СТОЯЛО ЗА ЗАКРИТИМИ ВОРОТАМИ ПЛОЩІ ───────────────────
    ЩО ЦЕ МІНЯЄ (правило 3, before/after; друге проходження, 17.09.2026).
    `суд_образу.review` виносить колірну гілку образу лише тоді, коли КОЖНА річ
    несе `джерело_площі` — і це не примха: частка площі рахується від суми по
    ЦІЛОМУ образу, тож над підмножиною вона хибна (`проби/comp_K-COMP-03-05.py`
    міряє це двома боками: заглушка 1/N одночасно народила три хибні знахідки й
    проковтнула справжню).
      before — базова трійка `прогін_зібраного` походження площі має
               (`джерело_площі="геометрія"`, площі з `areas.образ_з_геометрії`),
               а всі 17 НАВМИСНИХ образів — НІ: у них `площа` виписана рукою й
               без походження. Отже образ «тотальна теракота під відкритим
               кардиганом», доданий РІВНО заради K-SIL-07, до свого правила не
               доїжджав: ворота площі закриті, K-COL-01 не народжується, і
               множник ×0.6 разом із полем `також_правила=["K-SIL-07",
               "K-SIL-04"]` не з'являється нізвідки. Гейт звітував K-SIL-07
               мертвим НА ВЛАСНОМУ ОБРАЗІ, і причина була в батареї.
      after  — образ, який оголосив `верх_см`/`низ_см` на кожній речі, дістає
               площу з ГЕОМЕТРІЇ, як і базова трійка.
    ЧОМУ НЕ ДОПИСАТИ `джерело_площі="геометрія"` РУКОЮ. Це була б хибна
    провенанція: поле каже, ЗВІДКИ число, і поставити його над числом, виписаним
    рукою, означало б збрехати судді рівно в тому полі, яким він і вирішує, чи
    можна числу вірити. Тому площа тут ПЕРЕРАХОВУЄТЬСЯ, а образи без оголошених
    см лишаються як були — і їхні правила чесно лишаються за воротами.
    """
    import areas
    сирі = [dict(id=str(r.get("id")), верх_см=r["верх_см"], низ_см=r["низ_см"],
                 припуск=r.get("припуск", "straight"))
            for r in речі if r.get("верх_см") is not None and r.get("низ_см") is not None]
    if len(сирі) != len(речі):
        return [dict(r) for r in речі]      # не всі речі оголосили край — не брешемо
    try:
        гео = {g["id"]: g for g in areas.образ_з_геометрії(профіль, сирі)}
    except Exception:
        return [dict(r) for r in речі]
    вих = []
    for r in речі:
        g = гео.get(str(r.get("id")))
        вих.append(dict(r) if not g else dict(r, площа=g["площа"], near=g["near"],
                                              джерело_площі="геометрія"))
    return вих
