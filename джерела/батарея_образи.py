# Причина структурна: два паралельні списки, які ніщо не тримає разом. Тепер ціль
# і образ їдуть однією парою — розійтись їм нема як, а сімнадцятий образ,
# доданий заради ВХОДУ (сльота з реагентами), несе ціль `None` і звітується
# окремо, а не проти чужого ID.
# ШАБЛОН ТУТ БУВ П'ЯТИЙ І НАЙВУЖЧИЙ: `[KR]` проти `[KRE]` двадцятьма рядками
