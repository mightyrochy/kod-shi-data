# просто не бачив і мовчки віддавав None — тобто «образ заради входу», хоч ціль
# була названа. Тепер шаблон один на весь проєкт.


def ЦІЛЬ_ОБРАЗУ(чому):
    """ID правила з опису образу, або None, коли образ у батареї заради входу."""
    усі = ІП.усі_в_тексті(чому or "")
    return ІП.база(усі[0]) if усі else None


