# Слово, яким корпус називає «baby pink» (R-MUA-03): багато білого пігменту, мала
# хрома, холодний тон — у цьому лексиконі це рівно вікно «пудровий» (L 65–92,
# C 5–30, дуга 330–25°). Умова корпусу чіпляється до слова, а не до нового порогу.
_СЛОВО_ДИТЯЧОЇ_РОЖЕВОЇ = "пудровий"
# ITA-смуга «дуже світла» — те саме слово, яким `колір_простір_шкіра.ITA_BANDS`
# зве найсвітлішу смугу; корпус каже «very fair», і це вона.
_СМУГА_ДУЖЕ_СВІТЛА = "very light"


def _вікно(слово):
    """Вікно слова з лексикону: (L_низ, L_верх, C_низ, C_верх, дуга тону).

    Окрема функція, щоб звернення до `verify.ЛЕКСИКОН` було одне: сходинка, що
    посилається на слово, якого в лексиконі нема, має падати тут і поіменно."""
    в = V.ЛЕКСИКОН.get(слово)
    if в is None or в[4] is None:
        raise KeyError("слово «%s» не має вікна з дугою тону в лексиконі" % слово)
    return в


def _точка(слово, ч_тону, ч_світлоти, ч_хроми):
    """(L, C, h) сходинки: три частки вікна слова, хрома під стелею поверхні.

    Стеля — `c_max_поверхня` (R-COL-12, Pointer): помада — фарбована поверхня, і
    хроми, якої поверхня на цій світлоті не дає, сходинка не обіцяє. Верхній край
    вікна слова діє разом зі стелею: сходинка не має права вийти зі свого слова."""
    Llo, Lhi, Clo, Chi, дуга = _вікно(слово)
    h = (дуга[0] + ((дуга[1] - дуга[0]) % 360) * float(ч_тону)) % 360
    L = Llo + (Lhi - Llo) * float(ч_світлоти)
    стеля, _джерело = cs.c_max_поверхня(L, h)
    верх = min(float(Chi), стеля if стеля else float(Chi))
    C = Clo + max(0.0, верх - Clo) * float(ч_хроми)
    return L, C, h


def сходинки(hex_з_lch):
    """Сходинка відтінків помади: список рядків із hex, підписом і сім'єю.

    `hex_з_lch(L, C, h)` — рендер кольору, який передає викликач
    (`міст_основи._hex_lch`, той самий, яким малюються чипи шкіри/волосся/очей):
    один рендер на всю систему, без другої копії тут.

    Кожен рядок несе `слово` (як цю точку називає лексикон — це не підпис, а
    свідок виміру) і `lab` того hex, який людина справді побачить: міряємо
    показане, а не доокруглене."""
    import palettes as _PS
    ряд = []
    for підпис, сім_я, слово, ч_т, ч_с, ч_х in СХОДИНКИ:
        L, C, h = _точка(слово, ч_т, ч_с, ч_х)
        hexx = hex_з_lch(L, C, h)
        lab = cs.hx(hexx)
        назва, _як = _PS._назва(lab, виключити=V.МЕТАЛИ)
        ряд.append(dict(ключ=підпис, підпис=підпис, сім_я=сім_я, hex=hexx,
                        слово=слово, назва_виміру=назва, lab=lab,
                        L=round(lab[0], 1), C=round(cs.lch(lab)[1], 1),
                        h=round(cs.lch(lab)[2], 1)))
    return ряд


def _вісь_контрасту(lab, L_шкіри, L_обличчя, контраст):
    """(зійшлась, причина) для осі контрасту R-MUA-03 × K-CLR-03 × K-CLR-02.

    ДВА РІЗНІ СВІДКИ, І КОЖНА ПРИЧИНА НАЗИВАЄ СВОГО — бо питання теж два.
      · КРОК міряється проти ШКІРИ. R-MUA-03 каже «contrast against the
        complexion», і complexion — це шкіра, не зона обличчя. Крок є тоді, коли
        `важіль_макіяжу` виходить на свою стелю (`ВАЖІЛЬ_МАКІЯЖУ_L`, один крок
        Манселл-Value): функція обрізає вимір цією стелею сама, тож «важіль ==
        стеля» і означає «повний крок, який K-CLR-03 дозволяє взяти».
      · ПЕРЕБІР міряється проти ЗОНИ ОБЛИЧЧЯ. Питання тут інше — скільки контрасту
        біля обличчя ця особа взагалі несе (K-CLR-02), а зона обличчя зважена
        волоссям (K-CLR-04). Стеля — `дозволений_контраст` тієї самої особи: її
        власний `value_gap` плюс крок, який цій помаді дає важіль.
    Обидва числа з `face_contrast`; другого означення контрасту тут нема."""
    if L_шкіри is None and L_обличчя is None:
        return True, None
    hexx = _hex(lab)
    if L_обличчя is not None:
        сира = abs(float(lab[0]) - float(L_обличчя))
        ліміт, _в = КОНТР.дозволений_контраст(контраст, макіяж={"губи": hexx},
                                              L_обличчя=L_обличчя)
        if сира > ліміт:
            return False, ("темніша, ніж твоє обличчя витримує" if lab[0] < L_обличчя
                           else "світліша, ніж твоє обличчя витримує")
    if L_шкіри is not None:
        важіль, _джерело = КОНТР.важіль_макіяжу({"губи": hexx}, L_шкіри)
        if важіль < КОНТР.ВАЖІЛЬ_МАКІЯЖУ_L:
            return False, ("світліша за твою шкіру — кроку контрасту не дасть"
                           if lab[0] >= L_шкіри
                           else "надто близька до твоєї шкіри — кроку контрасту не дасть")
    return True, None


def _вісь_підтону(lab, поз, вага):
    """(зійшлась, причина) для осі підтону R-MUA-03 через `bases._відхил_тону_ΔE`.

    Вага 0 — осі нема входу (очі ахроматичні чи їх не зчитано, карток біля обличчя
    теж). Тоді вісь МОВЧИТЬ і нічого не відкидає: «без входу» — це не «не пасує»."""
    import bases as _ОС
    if not вага:
        return True, None
    відхил = _ОС._відхил_тону_ΔE(lab, поз)
    if відхил <= float(РЕЄСТР.C["крок_ΔE00"]):
        return True, None
    return False, ("холодніша за твій підтон" if поз > 0 else "тепліша за твій підтон")


def _умови_R_MUA_03(сх, шкіра):
    """(зійшлось, причина) для двох іменованих умов R-MUA-03: олива й дитяча рожева."""
    if (шкіра.get("undertone") == "оливковий"
            and (сх.get("C") or 0.0) >= float(РЕЄСТР.C["hi_C"])):
        return False, "твоя шкіра оливкова — їй личать приглушені, ця надто гучна"
    if (сх.get("слово") == _СЛОВО_ДИТЯЧОЇ_РОЖЕВОЇ
            and шкіра.get("depth_band") != _СМУГА_ДУЖЕ_СВІТЛА):
        return False, "на твоїй шкірі це вже заява, а не нюд — білого пігменту забагато"
    return True, None


def _hex(lab):
    """«#rrggbb» із Lab з обрізанням каналів — той самий рендер, що `palettes._hex`."""
    import palettes as _PS
    return _PS._hex(lab)


def суд(сх, F, контраст, поз, вага):
    """(рекомендована, причина) для ОДНІЄЇ сходинки. Причина — з тієї осі, що впала.

    Порядок називання: контраст, підтон, іменовані умови R-MUA-03. Він не випадковий:
    K-CLR-01 ставить контраст першою віссю за вагою, і якщо впали обидві, жінці
    називається та, що важить більше."""
    шкіра = (F or {}).get("шкіра") or {}
    L_обличчя = (контраст or {}).get("L_обличчя")
    if L_обличчя is None:
        L_обличчя = КОНТР.value_обличчя(F)
    L_шкіри = (контраст or {}).get("L_шкіри")
    if L_шкіри is None:
        L_шкіри = шкіра.get("L")
    for перевірка in (lambda: _вісь_контрасту(сх["lab"], L_шкіри, L_обличчя, контраст),
                      lambda: _вісь_підтону(сх["lab"], поз, вага),
                      lambda: _умови_R_MUA_03(сх, шкіра)):
        добре, чому = перевірка()
        if not добре:
            return False, чому
    return True, None


def поділ(ряд, F, контраст, самозвіт=None, надійність=None):
    """«Рекомендовані тобі» і «решта» з названою причиною на кожну сходинку.

    Повертає dict(є, рекомендовані, решта, чому, підтон). `є=False` — профілю ще
    нема (жінка не пройшла знайомство): поділу не буде, ряд один, і `чому` каже це
    словами (чесне «без входу», CLAUDE.md п.4). Сума груп ЗАВЖДИ дорівнює довжині
    ряду: сходинка не зникає, вона лише переїжджає нижче."""
    import bases as _ОС
    if not F or not (F.get("шкіра") or {}).get("L"):
        return dict(є=False, рекомендовані=[], решта=[x["ключ"] for x in ряд],
                    причини={}, підтон=None,
                    чому="поки не знаю твоїх кольорів — покажу всі")
    поз, вага, джерело = _ОС._температура_людини(F, самозвіт, надійність)
    рек, решта, причини = [], [], {}
    for сх in ряд:
        добре, чому = суд(сх, F, контраст, поз, вага)
        if добре:
            рек.append(сх["ключ"])
        else:
            решта.append(сх["ключ"])
            причини[сх["ключ"]] = чому
    return dict(є=True, рекомендовані=рек, решта=решта, причини=причини,
                підтон=dict(позиція=round(поз, 3), вага=round(вага, 3), джерело=джерело),
                чому=None)


def свій(hexx, ряд, F, контраст, самозвіт=None, надійність=None):
    """Вердикт для кольору, названого рукою. Вибір НЕ блокується — лише називається.

    Той самий суд, що й для сходинки: свій колір не має привілею й не має кари."""
    import bases as _ОС
    if not isinstance(hexx, str) or not hexx.strip().startswith("#"):
        return None
    lab = cs.hx(hexx)
    if not F or not (F.get("шкіра") or {}).get("L"):
        return dict(hex=hexx, рекомендована=None, причина=None)
    поз, вага, _дж = _ОС._температура_людини(F, самозвіт, надійність)
