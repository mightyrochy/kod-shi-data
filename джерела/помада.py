    сх = dict(ключ="свій", підпис="свій відтінок", слово=назва, lab=lab,
              C=round(cs.lch(lab)[1], 1))
    добре, чому = суд(сх, F, контраст, поз, вага)
    return dict(hex=hexx, рекомендована=bool(добре), причина=чому)
