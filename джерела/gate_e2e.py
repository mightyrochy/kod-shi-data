# -*- coding: utf-8 -*-
"""НАСКРІЗНИЙ ГЕЙТ: чи спрацьовує шар формальності на речі, ЩО ПРИЙШЛА З ФІДУ.

Чому цей файл існує окремо від двох попередніх аудитів. Обидва вони міряли шар у
вакуумі: аудит_формальності подавав `тип` руками, аудит_фіду не доходив до правил.
Між ними лежала діра, яку не бачив жоден з них: `тип` читався в outfit.елементи й
НЕ КЛАВСЯ в елемент, а у фіді його ніхто не писав узагалі. Тобто K-KOH-02/05 не могли
спрацювати на реальному SKU ніколи — правило було не хибне, а без входу.

Цей прогін іде рівно тим шляхом, яким піде продукт:
    рядок фіду → feed.тип_речі → outfit.елементи → формальність_образу

Прогін: `python3 наскрізний_гейт.py`
ЧОГО НЕ ДОВОДИТЬ: речі синтетичні (hex замість виміряного фото), тіла нема,
вердикту людини нема. Доводить рівно одне — ланцюг більше не рветься посередині.
"""
import colorspace as cs, feed, outfit as O, profile as PR

# рядки в тому вигляді, в якому їх віддає feed.прогін (без lab-виміру — hex задано руками)
РЯДКИ = [
    dict(id="a1", слот="верх",   назва="Блуза шовкова кремова",       категорія="Одяг / Блузи",
         hex="#efe3d0"),
    dict(id="a2", слот="низ",    назва="Джинси прямі індиго",         категорія="Одяг / Джинси",
         hex="#3d4d6b"),
    dict(id="a3", слот="взуття", назва="Човники замшеві чорні",       категорія="Взуття / Туфлі-човники",
         hex="#23212a"),
    dict(id="a4", слот="взуття", назва="Кросівки білі шкіряні",       категорія="Взуття / Кросівки",
         hex="#e9e9e6"),
    dict(id="a5", слот="верх",   назва="Світшот оверсайз сірий",      категорія="Одяг / Світшоти",
         hex="#8d8f8c"),
    dict(id="a6", слот="сукня",  назва="Вечірня сукня в підлогу",     категорія="Одяг / Сукні",
         hex="#1e2a3a"),
]


def _річ(р, площа=0.3, near=0.2):
    """Те, що конвеєр складає перед перевіркою образу."""
    return dict(id=р["назва"], слот=р["слот"], hex=р["hex"], площа=площа, near=near,
                тип=feed.тип_речі(р), джерело_площі="ручна")


def прогін():
    F = cs.features(cs.hx("#e8c4ad"), cs.hx("#a08e73"), cs.hx("#7b8fa1"))
    впало = 0
    print("=" * 78)
    print("НАСКРІЗНО: рядок фіду → тип → інтервал → гіперребро")
    print("=" * 78)

    print("\n%-32s %-16s %s" % ("рядок фіду", "тип (feed)", "інтервал (outfit)"))
    for р in РЯДКИ:
        т = feed.тип_речі(р)
        print("%-32s %-16s %s" % (р["назва"][:32], т, O.ТИП_ІНТЕРВАЛ.get(т)))

    образи = [
        ("блуза + джинси + човники", ["a1", "a2", "a3"],
         "high-low: має ПРОЙТИ (точкова модель це таврувала)"),
        ("блуза + джинси + кросівки", ["a1", "a2", "a4"],
         "звичайний денний образ: має пройти"),
        ("вечірня сукня + кросівки",  ["a6", "a4"],
         "справжній розрив: має спрацювати"),
        ("світшот + джинси + човники", ["a5", "a2", "a3"],
         "один свідомий розрив: якщо спрацює — має бути ослаблено (K-KOH-03)"),
    ]
    print("\n" + "─" * 78)
    for назва, ids, очікування in образи:
        речі = [_річ(next(r for r in РЯДКИ if r["id"] == i)) for i in ids]
        E = O.елементи(речі)
        зн = O.формальність_образу(E)
        k2 = [z for z in зн if z["правило"] == "K-KOH-02"]
        print("\n%-30s  %s" % (назва, очікування))
        інт = [(e["річ"], O.інтервал_формальності(e)) for e in O.одна_на_річ(E)]
        print("   інтервали: " + " · ".join("%s %s" % (n[:14], i) for n, i in інт))
        if not k2:
            print("   → спільний рівень Є, знахідки нема")
        for z in k2:
            print("   → K-KOH-02 сила %.2f  %s" % (z["сила_нп"], z["суть"]))
            print("      %s" % z["чому"][:150])

    # ── гейти ────────────────────────────────────────────────────────────────
    def спрацювало(ids):
        речі = [_річ(next(r for r in РЯДКИ if r["id"] == i)) for i in ids]
        зн = O.формальність_образу(O.елементи(речі))
        return next((z for z in зн if z["правило"] == "K-KOH-02"), None)

    print("\n" + "─" * 78)
    гейти = [
        ("тип постачається фідом (поле більше не сирота)",
         all(feed.тип_речі(р) for р in РЯДКИ)),
        ("інтервал доїжджає до правила через outfit.елементи",
         O.інтервал_формальності(O.елементи([_річ(РЯДКИ[0])])[0]) == (4.0, 7.0)),
        ("high-low блуза+джинси+човники ПРОХОДИТЬ", спрацювало(["a1", "a2", "a3"]) is None),
        ("вечірня сукня + кросівки СПРАЦЬОВУЄ", спрацювало(["a6", "a4"]) is not None),
        ("свідомий розрив ослаблений (сила < 0.5)",
         (лам := спрацювало(["a5", "a2", "a3"])) is None or лам["сила_нп"] < 0.5),
    ]
    for назва, ок in гейти:
        print(("  ✓ " if ок else "  ✗ ПРОВАЛ ") + назва)
        впало += (not ок)

    # ── жорстке «ні» на тих самих рядках ─────────────────────────────────────
    лишилось, прибрано = PR.жорсткі_ні(РЯДКИ, ["кросівки", "замш"])
    print("\n  жорстке «ні» = [кросівки, замш]: лишилось %d із %d, прибрано %s"
          % (len(лишилось), len(РЯДКИ), [(p["назва"][:22], p["через"]) for p in прибрано]))
    ок = len(прибрано) == 2
    print(("  ✓ " if ок else "  ✗ ПРОВАЛ ") + "абсолютний фільтр прибирає, а не знижує ранг")
    впало += (not ок)

    print("\n" + "=" * 78)
    print(("ЛАНЦЮГ ЦІЛИЙ" if not впало else "ПРОВАЛІВ: %d" % впало) +
          "  —  але речі синтетичні, тіла нема, вердикту людини нема.")
    print("=" * 78)
    return впало


if __name__ == "__main__":
    raise SystemExit(прогін())
