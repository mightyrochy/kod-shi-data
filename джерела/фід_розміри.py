# ── ПОВНОТА Й РОЗМІРНІСТЬ: ДРУГА Й ТРЕТЯ ОСІ ПОСАДКИ ВЗУТТЯ (17.09.2026) ────
# K-SHO-14 каже, що ШИРИНА — незалежна вісь, а K-SHO-15 — що розмір це ворота,
# ніколи не скор. Обидва читали б `устілка_см`, якої цей фід не дає жодного разу
# (свідоме рішення вище: розмірна таблиця глушить одиничне читання). Але картка
# несе дві ІНШІ осі тими самими словами, якими про них говорить майстерня.
# ВИМІРЯНО на `каталог_повний.xml` (2 096 взуття):
#   `повнота`     — 151 річ (7.2 %): «середня» 145, «вузька» 6;
#   `розмірність` — 28 речей (1.3 %) ПІСЛЯ зняття шаблону магазину.
# ⚠ ШАБЛОН МАГАЗИНУ ЗНІМАЄТЬСЯ ПЕРШИМ, І ЦЕ НЕ ДРІБНИЦЯ. Рядок «певні можуть
# відповідати стандартному розміру, деякі — маломірять або повномірять» стоїть у
# 91 картці ОДНОГО магазину й не каже про ЦЮ пару нічого: це загальне
# застереження, а не вимір. Без його зняття «маломірить» ловилось би на 91 речі
# замість 28 — той самий клас помилки, що вже двічі спійманий у цьому файлі
# (устілка = євророзмір, підошва «ЕВА» з «Беж-ЕВА»): патерн ловить власний
# приклад і видає загальний текст за властивість речі.
_ШАБЛОН_РОЗМІРНОСТІ = __import__("re").compile(
    r"деякі\s*[-–—]\s*маломірять\s+або\s+повномірять")
_ПРО_ПОВНОТУ = __import__("re").compile(
    r"(вузьк|середн|широк)\w*\s+(?:повнот|колодк)|"
    r"(?:повнот|колодк)\w*[\s:—–-]*(?:модел\w*[\s:—–-]*)?(вузьк|середн|широк)")
_ПРО_РОЗМІРНІСТЬ = __import__("re").compile(r"(маломір|повномір|великомір)\w*")
_ПОВНОТА_СЛОВО = {"вузьк": "вузька", "середн": "середня", "широк": "широка"}
_РОЗМІРНІСТЬ_СЛОВО = {"маломір": "маломірить", "повномір": "повномірить",
                      "великомір": "великомірить"}
# ── K-SIZ-02: НОМІНАЛЬНИЙ РОЗМІР — ЦЕ ПИТАННЯ, А НЕ ПОСАДКА (19.09.2026) ────
# ВХІД БУВ І НЕ ЧИТАВСЯ. Корпус (тема-7) каже: «a nominal size without garment
# measurements is a question, never a "fits"», FORCE `strong` для МЕХАНІЗМУ і
# `hint` для КОЖНОГО числа (розкид «≈10 см» / «≈12 см» — `[folkloric]`, порогом
# ставити заборонено; тут їх і нема). Картка при цьому мітки розміру несе:
# ВИМІРЯНО на `каталог_повний.xml.gz` (12 426 оферів, 8 617 одягу):
#   param `розміри` — 10 584 офери, з них одягу 8 261 (95.9 % одягу);
#   param `~розмір` — 4 673; param `розміри_в_наявності` — 1 511.
# Тобто мітка є майже всюди, а код її не бачив узагалі — розмір мовчав, і жінка
# діставала образ без жодного слова про те, чи існує він у її номері. Після
# СТРОГОГО розбору (нижче) мітку дістають 7 179 речей одягу з 8 589 (83.6 %):
# різниця між 95.9 % і 83.6 % — це рядки, у яких магазин поставив не розмір
# (обхвати, власні коди товару), і вигадувати з них мітку тут ніхто не буде.
#
# ЧОМУ МІТКИ, А НЕ ЧИСЛО. Рядок магазину мішаний за побудовою: у 8 617 речах
# одягу стоїть 270 різних токенів — літери (M 3 777, S 3 687, L 3 312, XS 2 746,
# XL 2 442), українські номери (42 — 2 488, 44 — 2 480, 46 — 2 184), смуги
# («42-44» 1 242), пари («S/M» — одна мітка, і саме тому «/» НЕ є роздільником),
# «ONE SIZE» (602) і явні «S НЕМА» (816) — тобто позначка ВІДСУТНОСТІ розміру,
# яку прочитати як наявний розмір означало б пообіцяти те, чого в магазині нема.
# Тому тут не вгадується жодне число: мітки нормуються, нерозпізнані лишаються
# окремим полем (мовчання не видається за відсутність), а смуга для людини
# будується з країв — «42–48», «S–XL».
#
# ДРУГА ПОЛОВИНА ПРАВИЛА — ПОЗА ВХОДОМ, І ЦЕ СКАЗАНО, А НЕ ЗАМОВЧАНО. Пофірмовий
# зсув мірок береться з таблиці розмірів бренду, і R-ONT-09 називає її шлях:
# «brand size tables are scraped, never ingested» — таблиця в Rozetka подається
# тікетом у підтримку, машинного ендпойнта не має. Чекліст «без входу» стоїть у
# `status.список()` (`довжина_виробу_см`), і посилання на R-ONT-09 лежить там.
ДІАПАЗОН_РОЗМІРУ_ОДЯГУ = (32, 60)
# Межі — ОБЛАСТЬ ВИЗНАЧЕННЯ мітки, не поріг рішення: за ними двозначне число в
# рядку розмірів не є українським розміром одягу (у тих самих рядках стоять
# обхвати «80/84/88/92/96» і джинсові дюйми «24…28» — це інші шкали, і читати
# їх розміром означало б вигадати мітку, якої магазин не ставив).
_ПОРЯДОК_ЛІТЕР = ("XXS", "XS", "S", "M", "L", "XL", "XXL", "XXXL")
_РОЗМІР_СЕП = __import__("re").compile(r"[,;]")
# «нема» коло мітки — це слово магазину про ВІДСУТНІСТЬ, а не частина мітки
_РОЗМІР_НЕМА = __import__("re").compile(r"\b(нема|немає|нет)\b", __import__("re").I)
_РОЗМІР_СМУГА = __import__("re").compile(r"^(\d{2})\s*[-–—]\s*(\d{2})$")
_РОЗМІР_КРАТНИЙ = __import__("re").compile(r"^([234])XL$")


def _мітка_розміру(т):
    """Одна мітка розміру одягу → канонічна форма, або None («не розпізнано»).

    None тут — НЕ «розміру нема»: це третій стан, який їде окремим полем
    `розміри_нерозпізнано`. Різниця вирішальна рівно так само, як у
    `взуттєві_атрибути`: на None правило виходить питанням, а не вердиктом."""
    т = " ".join((т or "").upper().split())
    if not т:
        return None
    м = _РОЗМІР_КРАТНИЙ.match(т)
    if м:                                   # «2XL» і «XXL» — та сама мітка
        т = "X" * int(м.group(1)) + "L"
    if т in _ПОРЯДОК_ЛІТЕР or т == "ONE SIZE":
        return т
    if _РОЗМІР_СМУГА.match(т):
        a, b = (int(x) for x in _РОЗМІР_СМУГА.match(т).groups())
        if all(ДІАПАЗОН_РОЗМІРУ_ОДЯГУ[0] <= x <= ДІАПАЗОН_РОЗМІРУ_ОДЯГУ[1] for x in (a, b)):
            return "%d-%d" % (a, b)
        return None
    if "/" in т:                            # «S/M», «XS/S» — одна мітка на дві літери
        частки = [_мітка_розміру(ч) for ч in т.split("/")]
        if частки and all(ч in _ПОРЯДОК_ЛІТЕР for ч in частки):
            return "/".join(частки)
        return None
    if т.isdigit() and len(т) == 2:
        if ДІАПАЗОН_РОЗМІРУ_ОДЯГУ[0] <= int(т) <= ДІАПАЗОН_РОЗМІРУ_ОДЯГУ[1]:
            return т
    return None


def _ранг_мітки(м):
    """Порядок мітки на шкалі: номер за числом, літера за _ПОРЯДОК_ЛІТЕР."""
    к = м.split("-")[0].split("/")[0]
    if к.isdigit():
        return (0, int(к))
    if к in _ПОРЯДОК_ЛІТЕР:
        return (1, _ПОРЯДОК_ЛІТЕР.index(к))
    return (2, 0)


def розміри_одягу(offer):
    """Мітки розміру картки для K-SIZ-02: що магазин НАЗВАВ, без жодного здогаду.

    Віддає лише непорожні ключі (той самий ідіом, що `взуттєві_атрибути`):
      `розміри`              — мітки в наявності, за шкалою;
      `розміри_нема`         — мітки, коло яких магазин сам написав «нема»;
      `розміри_шкала`        — «номер» / «літера» / «мішана»;
      `розміри_нерозпізнано` — сирі токени, які прочитати не вдалось.
    """
    пар = offer.get("параметри") or {}
    сире = ""
    for к in ("розміри_в_наявності", "розміри", "розмір", "~розмір"):
        if (пар.get(к) or "").strip():
            сире = пар[к]; break
    if not сире:
        return {}
    є, нема, сміття = [], [], []
    for токен in _РОЗМІР_СЕП.split(сире):
        т = токен.strip()
        if not т:
            continue
        відсутній = bool(_РОЗМІР_НЕМА.search(т))
        м = _мітка_розміру(_РОЗМІР_НЕМА.sub(" ", т) if відсутній else т)
        if м is None:
            сміття.append(т[:24])
        elif відсутній:
            нема.append(м)
        else:
            є.append(м)
    впор = lambda сп: tuple(sorted(dict.fromkeys(сп), key=_ранг_мітки))
    є, нема = впор(є), впор(нема)
    шкали = {("номер" if _ранг_мітки(м)[0] == 0 else "літера") for м in є}
    вих = dict(розміри=є or None, розміри_нема=нема or None,
               розміри_шкала=(("мішана" if len(шкали) > 1 else шкали.pop()) if шкали else None),
               розміри_нерозпізнано=впор(сміття) or None)
    return {k: v for k, v in вих.items() if v is not None}


def смуга_розмірів(р):
    """Мітки речі однією смугою для людини: «42–48», «S–XL», «46». None — міток нема.

    Смуга, а не перелік: корпус вимагає показувати розмір ДІАПАЗОНОМ, і перелік
    із восьми міток у рядку вердикту читається як асортимент, а не як межа.

    ДВІ ШКАЛИ НЕ ЗЛИВАЮТЬСЯ В ОДНУ СМУГУ. У мішаному рядку («51, L, M, ONE SIZE,
    S») кінці належать різним шкалам, і «51–ONE SIZE» було б не межею, а
    склеєними уламками двох. Тому смуга будується ОКРЕМО по номерах і по літерах,
    а «ONE SIZE» у кінці смуги не стоїть ніколи: це не точка на шкалі."""
    м = [x for x in ((р or {}).get("розміри") or ()) if x != "ONE SIZE"]
    смуги = []
    for рід in (0, 1):
        ш = [x for x in м if _ранг_мітки(x)[0] == рід]
        if not ш:
            continue
        a = ш[0].split("-")[0].split("/")[0]
        b = ш[-1].split("-")[-1].split("/")[-1]
        смуги.append(a if a == b else "%s–%s" % (a, b))
    if смуги:
        return " і ".join(смуги)
    return "один розмір" if "ONE SIZE" in ((р or {}).get("розміри") or ()) else None


def розмірність_речі(offer):
    """Слово магазину про розмірність («маломірить») для БУДЬ-ЯКОЇ речі, не лише пари.

    ЩО ЦЕ МІНЯЄ. Той самий розбір стояв усередині `взуттєві_атрибути`, тобто
    працював рівно на слоті «взуття» (28 пар після зняття шаблону магазину).
    ВИМІРЯНО на `каталог_повний.xml.gz`: поза взуттям те саме слово стоїть ще на
    6 речах одягу (сукня 2, низ 3, верх 1; магазини cooshwear.com, ricamare.com.ua)
    — число мале й чесне, і саме воно є другим свідком K-SIZ-02: там, де магазин
    САМ каже, що номер бреше, питання про посадку перестає бути загальним.
    ⚠ Шаблон магазину знімається першим — див. `_ШАБЛОН_РОЗМІРНОСТІ`."""
    текст = ("%s %s %s" % (offer.get("категорія", ""), offer.get("назва", ""),
                           offer.get("опис", "") or "")).lower()
    м = _ПРО_РОЗМІРНІСТЬ.search(_ШАБЛОН_РОЗМІРНОСТІ.sub(" ", текст))
    return _РОЗМІРНІСТЬ_СЛОВО.get(м.group(1)) if м else None

# Слоти, де мітка розміру говорить про ОДЯГ (K-SIZ-02). Взуття сюди не входить:
# його розмір — інша шкала (34–44) і інший шар (`аксесуари_розмір`), а сумка,
# пояс і прикраси несуть у тому самому полі довжину ременя чи діаметр — не розмір.
СЛОТИ_РОЗМІРУ_ОДЯГУ = ("верх", "низ", "сукня", "верхній_шар", "комплект")
