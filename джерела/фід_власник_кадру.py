# -*- coding: utf-8 -*-
"""фід_власник_кадру.py — ЧИЙ кадр виміру: один запис власності кадру на товар (наряд 5.2).

ЩО БУЛО (main cdf6bec, `каталог_повний`, 15 830 записів). Власність кадру вгадувалась у трьох
місцях, і кожне — сім'єю тону чи словом: `фід_варіант` брав слово варіанта, «тієї ж сім'ї
тону», що вимір кадру чи слово в імені файла (64 записи, ж-02639@sunwin: блакитний светр став
«капучино», бо «срібний» вимір і «капучино» — одна сім'я), `фід_кадр_колір.після_спору`
ставив на картку першим кадр галереї, чий вимір тієї ж сім'ї, що слово крамниці (59 карток
«свій_кадр»: креслення ж-02894, чотири пари взуття ж-09933), а кадр жнив, що стоїть ще й на
ІНШОМУ товарі, ішов у вимір як фото цієї речі: за маніфестом кадрів (`каталог_маніфест_кадрів`,
sha256 вмісту) таких 522 записи з 10 774, чий кадр жнив маніфест знає, — пасок likeangel
міряний зі светра «фуксія», молочна сукня twice — з кадру коричневої сестри.

ЩО СТАЛО. Факт власності — лише байти: sha256 кадру виміру з маніфесту кадрів і перелік
інших товарів фіду, у чиїх галереях ті самі байти. Факти пише прилад збирача
(`прилади/власник_кадру.py`, маніфест є лише в нього) у `каталог_власник_кадру.json.gz` поруч
із модулем, збирач сторінки кладе файл у вантаж; тут він лише читається. Запис (`запис`):
  товар, кадр (адреса виміру), джерело («кадр_виміру» — контракт 5655, «кадр_жнив» — історичний
  запис), sha256 (12 знаків), клас (вимір галереї, `фід_кадр_колір.клас_кадру`), варіант
  (лише явний — артикул чи єдиний варіант у полі, `фід_варіант`; інакше «невідомо»), стан і чому:
  · «спільний» — ті самі байти стоять на інших товарах (дубль пропозиції — та сама назва й
    поле кольору — не інший товар): чий кадр, не доведено, і для
    виміру він чужий (`чужий_кадр_речі`, той самий шлях, що спільна картинка крамниці);
  · «свій» — байти є в галереї цього товару й більше ніде;
  · «невідомо» — фактів нема (кадр поза маніфестом, файл фактів знято з іншого кадру чи його
    нема у вантажі) або кадра нема в галереї товару. Вимір і картка тоді — як доти: зв'язок
    не підтверджено, але й чужим не доведено, а вгадувати його код не бере.
Сім'я тону, слово крамниці й ім'я файла сюди не входять: це сигнал мовній моделі, не доказ (п.12).
Те саме для решти галереї (`спільні_файли`): файл, чиї байти стоять і на інших товарах, — груповий
кадр чи кадр сестри, і фото цієї речі він не стає.
Вимір кольору (`фід_каталог`) і ряд картки (`фід_фото.кадри_речі`) читають ті самі факти, тож
рішення одне на двох читачів.
"""
import json, os, zlib
from фід_фото import файл_фото, чужий_кадр, стан_кадру_виміру

ВЛАСНИК_ІМ = "каталог_власник_кадру.json"
ЧОМУ_СПІЛЬНИЙ = "той самий вміст кадру (sha256) стоїть на інших товарах — власника не доведено"
_КЕШ = {}


def читати_факти(тека=None):
    """{ід: [crc32 адреси кадру | None, sha256[:12] | None, байти в галереї товару, [інші ід],
    [спільні файли галереї]]} поруч із модулем;
    файла нема — порожньо (збірка без фактів: кожен запис «невідомо», вимір і картка як доти)."""
    тека = тека or os.path.dirname(os.path.abspath(__file__)) or "."
    for ш in (os.path.join(тека, ВЛАСНИК_ІМ + ".gz"), os.path.join(тека, ВЛАСНИК_ІМ)):  # .gz першим, як решта даних
        if not os.path.exists(ш):
            continue
        ключ = (ш, os.path.getmtime(ш))
        if ключ not in _КЕШ:
            import gzip as _gz
            with (_gz.open(ш, "rt", encoding="utf-8") if ш.endswith(".gz") else open(ш, encoding="utf-8")) as f:
                _КЕШ.clear()
                _КЕШ[ключ] = json.load(f).get("записи") or {}
        return _КЕШ[ключ]
    return {}


def crc_адреси(url):
    """Відбиток адреси кадру у файлі фактів: факт діє, лише поки кадр виміру той самий."""
    return "%08x" % (zlib.crc32(str(url).encode("utf-8")) & 0xFFFFFFFF)


def адреса_кадру(зб):
    """(адреса, джерело) кадру, з якого виміряно запис збагачення, або (None, None)."""
    if not isinstance(зб, dict):
        return None, None
    if isinstance(зб.get("кадр_виміру"), dict) and зб["кадр_виміру"].get("url"):
        return зб["кадр_виміру"]["url"], "кадр_виміру"
    return (зб.get("фото"), "кадр_жнив") if зб.get("фото") else (None, None)


def запис(o, зб, вар=None, к=None, факти=None):
    """Запис власності кадру виміру товару `o` (dict, див. докстрінг модуля) або None — кадру нема.

    `вар` — слово варіанта `фід_варіант.слово_моделі` (явне або None), `к` — контекст
    `фід_кадр_колір` (для класу кадру; без нього клас None), `факти` — `читати_факти()`."""
    url, джерело = адреса_кадру(зб)
    if not url:
        return None
    ід = o.get("id")
    р = dict(товар=ід, кадр=url, джерело=джерело, sha256=None, клас=None, товари=[],
             варіант=(вар or {}).get("слово") or "невідомо", стан="невідомо", чому="no_hash_fact")
    if к is not None:
        from фід_кадр_колір import клас_кадру
        р["клас"] = клас_кадру(ід, url, к)
    ф = (читати_факти() if факти is None else факти).get(ід)
    if джерело == "кадр_виміру":
        р["sha256"] = str(зб["кадр_виміру"].get("sha256") or "")[:12] or None
        if стан_кадру_виміру(o, зб)["стан"] != "measured":
            р["чому"] = "measurement_provenance_unknown"
            return р
    if not ф or ф[0] != crc_адреси(url) or not (ф[1] or р["sha256"]):
        return р  # без байтів не доведено ні «свій», ні «спільний»
    р["sha256"] = р["sha256"] or ф[1]
    у_галереї = ф[2] or файл_фото(url) in {файл_фото(x) for x in (o.get("фото") or ()) if x}
    if ф[3]:
        р.update(стан="спільний", чому="frame_shared_by_items", товари=list(ф[3]))
    elif у_галереї:
        р.update(стан="свій", чому="own_frame")
    else:
        р["чому"] = "frame_not_in_gallery"
    return р


def спільні_файли(o, факти=None):
    """Файли галереї (`файл_фото`) товару `o`, чиї байти стоять і на інших товарах фіду.

    Груповий кадр (костюм і штани з нього, сукня з паском) чи кадр сестри-варіанта: чий він,
    байти не кажуть, тож фото цієї речі він не стає (`фід_фото.кадри_речі`)."""
    ф = (читати_факти() if факти is None else факти).get(o.get("id"))
    return set(ф[4]) if ф and len(ф) > 4 else set()


def чужий_кадр_речі(o, url, спільні, факти=None):
    """Чому кадр `url` не фото речі `o` — dict як `фід_фото.чужий_кадр` — або None.

    Спільна картинка крамниці за іменем файла (`чужий_кадр`) або ті самі байти на інших
    товарах (`запис` «спільний»). Читають вимір кольору (`фід_каталог`) і картка
    (`міст_опис`) — одне рішення для обох."""
    if not url:
        return None
    чуже = чужий_кадр(url, спільні)
    if чуже:
        return чуже
    р = запис(o, {"фото": url}, факти=факти)
    if р and р["стан"] == "спільний":
        return dict(файл=файл_фото(url), товарів=1 + len(р["товари"]), чому=ЧОМУ_СПІЛЬНИЙ,
                    sha256=р["sha256"], товари=р["товари"])
    return None
