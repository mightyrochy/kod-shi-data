def верхні_атрибути(offer, тип=None):
    """Атрибути верхнього шару з категорії, назви, опису й параметрів.

    None означає «не названо», НЕ «нема»: різниця вирішальна рівно так само, як у
    взуттєвих атрибутах. На None правило теми-11 виходить ПИТАННЯМ із названим
    блокером, на False — вердиктом. Мовчазний дефолт тут був би найдорожчою помилкою
    файлу: половина правил теми (стан, драбина припусків, ремонтопридатність)
    вмикається саме наявністю атрибута.

    ДВІ ОСІ РУКАВА, ЯКІ НЕ ЗЛИВАЮТЬСЯ (12.09.2026, наряд Н-V14-031). Поле `рукав`
    тут — це КРІЙ ПРОЙМИ (`реглан` / `вшивний`), і читають його K-OUT-33 (мʼяке
    плече не тримає накинутого шару) та K-OUT-39 (комір і крій рукава разом);
    22.7 % речей верхнього шару, і джерело — слово тексту. Поруч у записі каталогу
    лежить `рукав_слово` — це ДОВЖИНА рукава з param `рукав_рівень` (154 офери
    верхнього шару: «довгий» 140 · «без рукавів» 10 · «3/4» 4), і читає його
    `outfit.зони_речі` (вісь покриття «руки»). Це ДВА різні питання про ту саму
    річ — крій пройми проти довжини, — і злити їх означало б дати K-OUT-33 вхід із
    чужої шкали: «довгий» не є ні регланом, ні вшивним. Записано тут, а не лише в
    коміті, щоб наступний прохід не «полагодив» два поля в одне.
    """
    сл = слот(offer)
    альт = _альтернативні_слоти(offer, сл) if сл else ()
    if сл != "верхній_шар" and "верхній_шар" not in альт:
        return {}
    текст = ("%s %s %s" % (offer.get("категорія") or "", offer.get("назва") or "",
                           offer.get("опис") or "")).lower()
    пар = offer.get("параметри") or {}
    if isinstance(пар, str):
        try: пар = __import__("ast").literal_eval(пар)
        except Exception: пар = {}
    текст_пар = " ".join("%s %s" % (k, v) for k, v in пар.items()).lower()
    повний = текст + " " + текст_пар
    a = {}
    for т, ключі in ТИП_ВЕРХНЬОГО_КЛЮЧІ:
        if any(k in повний for k in ключі):
            a["тип_верхнього"] = т; break
    # ── БОРТНІСТЬ І ЗАСТІБКА: PARAM ПЕРЕД ТЕКСТОМ (12.09.2026, наряд Н-V14-031) ─
    # ЩО ЦЕ МІНЯЄ (before/after, каталог_повний, 764 офери слота верхній_шар).
    # ВИМІР: param `бортність` є на 189 оферах зі значеннями «двобортне» 92 ·
    # «на блискавці» 82 · «без застібки» 12 · «однобортне» 3. Гілка читала ЛИШЕ
    # підрядок назви й опису, і те, що вона при цьому щось давала, — випадковість:
    # `повний` склеює текст зі ЗНАЧЕННЯМИ param (рядок вище), тож слово магазину
    # доїжджало сюди як чужа назва. Пріоритету не було зовсім, і назва «Пальто
    # однобортне» перекривала param «двобортне» — здогад підрядком бив твердження
    # продавця. Тепер param читається ПЕРШИМ, тим самим пріоритетом, що вже
    # застосований до `матеріал_верху` й `каблук_см` у взуттєвій гілці.
    #
    # ⚠ «НА БЛИСКАВЦІ» І «БЕЗ ЗАСТІБКИ» В `бортність` НЕ ЙДУТЬ. 94 офери з 189 —
    # це не бортність, а ТИП ЗАСТІБКИ: пальто на блискавці бортів не має взагалі,
    # і дати K-OUT-12 (глибина фронтального V) такий вхід означало б сплутати дві
    # осі — головний названий ризик наряду. Тому окреме поле `застібка` з трьома
    # значеннями (`блискавка` / `нема` / `ґудзики`); читає його `outer.стан`, де
    # відсутність бортності доти означала «невідомо», і — ЛИШЕ значенням «нема» —
    # `outer.фронтальний_V`.
    _борт_пар = str(пар.get("бортність") or "").strip().lower()
    if any(k in _борт_пар for k in ("двобортн", "двухбортн", "двубортн")):
        a["бортність"] = "двобортне"
    elif any(k in _борт_пар for k in ("однобортн", "одноборт")):
        a["бортність"] = "однобортне"
    elif any(k in повний for k in ("двобортн", "двухбортн", "двубортн", "double-breasted")):
        a["бортність"] = "двобортне"
    elif any(k in повний for k in ("однобортн", "одноборт", "single-breasted")):
        a["бортність"] = "однобортне"
    # ОСНОВИ, НЕ ПОВНІ ФОРМИ («на блискавці» / «блискавка» / «блискавкою» — один
    # корінь), і ЛИШЕ param: виводити тип застібки з опису означало б ловити
    # «блискавка» в «блискавка на кишені», а кишеня фронт не застібає.
    if any(k in _борт_пар for k in ("блискав", "молни", "zip")):
        a["застібка"] = "блискавка"
    elif "без застібк" in _борт_пар or "без застеж" in _борт_пар:
        a["застібка"] = "нема"
    elif "ґудзик" in _борт_пар or "гудзик" in _борт_пар:
        a["застібка"] = "ґудзики"
    # ── ПОЯС. K-OUT-08 (припуск стає інтервалом) і K-OUT-35 (звужує стани) ──
    if any(k in повний for k in ("з поясом", "на поясі", "поясом", "з ремінц", "куліск",
                                 "з паском", "паском", "belted")):
        a["пояс"] = True
    elif any(k in повний for k in ("без пояса", "без паска")):
        a["пояс"] = False
    # ⚠ КОМІР ЧИТАЄТЬСЯ ЛИШЕ В КОНТЕКСТІ СЛОВА «КОМІР/ВОРОТНИК». Перша версія брала
    # «класичн» окремо й записала б комір будь-якому «класичному пальту». Це та сама
    # пастка підрядка, що вже коштувала темі-10 тринадцяти рядків («кросбоді» → «боді»).
    _є_комір = ("комір" in повний or "воротник" in повний)
    for к, ключі in КОМІР_КЛЮЧІ:
        if any(x in повний for x in ключі) and (_є_комір or к == "без_коміра"):
            a["комір"] = к; break
    if "капюшон" in повний:
        a["капюшон"] = True
        if any(k in повний for k in ("знімн", "съемн", "відстібн", "отстегив")):
            a["капюшон_знімний"] = True
        # основи, не повні форми: «хутряним капюшоном» повз «хутряний капюшон»
        if "опушк" in повний or "з мехом" in повний or (
                any(k in повний for k in ("хутр", "хутро", "мех")) and "капюшон" in повний):
            a["опушка"] = True
    elif "без капюшона" in повний:
        a["капюшон"] = False
    if "реглан" in повний:
        a["рукав"] = "реглан"
    elif any(k in повний for k in ("вшивн", "втачн")):
        a["рукав"] = "вшивний"
    if any(k in повний for k in ("стьоган", "стьобан", "стеган", "простібк", "простеж",
                                 "quilted", "у ромб", "ялинк")):
        a["простібка"] = True
        # ⚠ ОРІЄНТАЦІЮ ЗАПИСУЄМО, АЛЕ ЗНАКУ ЇЙ НЕ ДАЄМО (K-OUT-25): два джерела кажуть
        # протилежне, а корпус уже має заборону стверджувати знак ефекту смуг у будь-який
        # бік (R-HELM-03, §VII.3 теми-4). Поле є, вердикту з нього не буде.
        if any(k in повний for k in ("горизонтальн", "поперечн")):
            a["простібка_орієнтація"] = "горизонтальна"
        elif any(k in повний for k in ("шеврон", "ялинк", "діагональн", "у ромб")):
            a["простібка_орієнтація"] = "нахилена"
    for в, ключі in _ВОРС_КЛЮЧІ:
        if any(k in повний for k in ключі):
            a["ворс"] = в; break
    if any(k in повний for k in ("оверсайз", "oversize", "вільного крою", "свободн", "вільний крій")):
        a["оверсайз"] = True
    for д, ключі in ДОВЖИНА_КЛЮЧІ:
        if any(k in повний for k in ключі):
            a["довжина_рівень"] = д
            a["довжина_джерело"] = "слово назви"
            break
    # ── НАПОВНЮВАЧ: PARAM `утеплювач` ПЕРЕД СЛОВНИКОМ ТЕКСТУ (наряд Н-V14-031) ─
    # ВИМІР (12.09.2026, каталог_повний): param `утеплювач` є на 139 із 764 оферів
    # верхнього шару зі значеннями «без утеплювача» 78 · «синтепон» 13 · «качине
    # перо (duck feather) – 10 %» 12 · «біопух» 7 · «Comfortemp®» 6 · «slimtex» 5 ·
    # «thinsulate™» 5. Словник `_НАПОВНЮВАЧІ` з тексту давав 97 із 618 речей
    # каталогу (15.7 %) — і param серед джерел не було.
    # ГОЛОВНЕ ТУТ НЕ ЧИСЛО, А `False`. «Без утеплювача» — це ОГОЛОШЕНА ВІДСУТНІСТЬ,
    # і вона мусить прийти як False, не як None: на None правило теми виходить
    # ПИТАННЯМ із названим блокером, на False — вердиктом. Це та сама різниця «нема»
    # проти «не названо», на якій стоїть докстрінг цієї функції, і без цього рядка
    # 78 оферів, де магазин сказав прямо, читались як мовчання.
    # ЗНАЧЕННЯ ПОЗА СЛОВНИКОМ ЛИШАЄТЬСЯ СЛОВОМ МАГАЗИНУ («біопух», «Comfortemp®»):
    # вигадувати їм корінь нема з чого, а викидати означало б знову читати
    # оголошене як мовчання. Та сама постанова, що для `матеріал` (Н-V14-029):
    # вузьке слово там, де словник його знає, рядок магазину там, де ні.
    _утепл = str(пар.get("утеплювач") or "").strip().lower()
    if "без утеплювача" in _утепл or _утепл.startswith("без "):
        a["наповнювач"] = False
    elif _утепл:
        a["наповнювач"] = next((н for н, ключі in _НАПОВНЮВАЧІ
                                if any(k in _утепл for k in ключі)), _утепл)
    else:
        for н, ключі in _НАПОВНЮВАЧІ:
            if any(k in повний for k in ключі):
                a["наповнювач"] = н; break
    м = _ПРО_ВОВНУ.search(повний)
    if м:
        a["вовна_частка"] = float(м.group(1) or м.group(2)) / 100.0
    м = _ПРО_FP.search(повний)
    if м:
        a["fill_power"] = int(м.group(1) or м.group(2))
    м = _ПРО_ГРАМАЖ.search(повний)
    if м:
        a["грамаж_г"] = int(м.group(1) or м.group(2))
    # K-OUT-15 — ВЕТО, А НЕ ПРАВИЛО: fill power без ваги наповнювача не інтерпретується.
    # Прапорець ставиться ТУТ, у місці зчитування, щоб жоден споживач не міг взяти FP
    # першим і назвати це теплом.
    if a.get("fill_power") is not None and a.get("грамаж_г") is None:
        a["fp_без_грамажу"] = True
    return a
