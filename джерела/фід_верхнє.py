def матеріал_речі(offer):
    """Читає перевірений код розбору без словникового запасного шляху."""
    поле = "material" if КД.ключ(offer, "material") else "fabric"
    return КД.ключ(offer, поле), КД.джерело_рядком(offer, поле)


def верхні_атрибути(offer):
    """Читає перевірений код розбору без словникового запасного шляху."""
    return КД.верхні(offer) if КД.код_слоту(offer) == "outerwear" or КД.код_типу(offer) in КД.СЛ.ДВОСЛОТОВІ_ТИПИ else {}
