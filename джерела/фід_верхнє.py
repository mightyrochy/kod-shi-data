# ВІДСОТОК, ЩО НАЛЕЖИТЬ НАСТУПНОМУ ВОЛОКНУ, — НЕ НАШ. dolcedonna пише склад без
# роздільників: «верх топ вовна 53%бавовна18%шовк15%віскоза». Тут «53» — частка
# БАВОВНИ, а не вовни, і слово «вовна» перед ним — назва кольору крамниці.
# Без цього погляду вперед розрізняч `(?<!ба)` міняв одне хибне число на інше
# (6 речей на каталог_повний). Тепер такий запис чесно мовчить: `None` означає
# «не названо», і шар виходить питанням, а не хибним вердиктом.
# БЕЗ `\s*` НАВМИСНО: роздільник (пробіл, кома) означає, що склад написано
# по-людськи й «вовна 60% поліестер 40%» — це справді 60 % вовни. Ловимо лише
# злиплий запис «53%бавовна», де відсоток стоїть ПЕРЕД своїм волокном.
_ЗА_ВІДСОТКОМ_ЧУЖЕ = r"(?!(?:бавовн|шовк|віскоз|льон|поліест|еластан|нейлон|акрил|лайкр|поліамід))"
# Одна буквена ознака волокна допустима з обох боків; чужі волокна — за чинним розрізнячем.
# Число перед волокном читається першим: `18% vergin wool 60% merino wool` — це 18 + 60.
# «г/м²» — щільність на площу полотна («наповнювач синтепух 150г/м²»), а не МАСА наповнювача
# в куртці: K-OUT-15 ділить fill power на масу, і щільність тут була б чужою величиною.
