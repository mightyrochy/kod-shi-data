"""фід_верхнє.py — атрибути верхнього шару (тема-11) КОДОМ: `верхні_атрибути` віддає лише `тип_верхнього` з коду типу речі.

Було (до рядка 5192, п.12): функція читала слова назви, категорії, опису й значень param — основи слів
типу, коміра, ворсу, наповнювача, відсотки складу, «без капюшона» — і з цього складала бортність, пояс,
капюшон, опушку, простібку, довжину, вовну, fill power. Тепер код слів не читає: властивість верхнього
одягу, якої нема в коді моделі (збагачення qwen верхнього рівня: крій, довжина, матеріал, візерунок),
лишається «невідомо» — ключа в записі нема, споживач виходить питанням, а не здогадкою зі слова.
"""
from фід_слот import (слот, _альтернативні_слоти)
import внутрішня_мова as ВМ

# ЩО ЦЕ МІНЯЄ В РІШЕННІ. Тип верхнього шару (пальто, куртка, пуховик…) — вісь теплової й конструктивної
# функції, окрема від `тип_речі`. Єдине джерело — код типу `item_type` у param `тип` (внутрішня мова);
# коди нижче — Латиницею, ключ ядра дає `внутрішня_мова.ключ`. Немає коду серед верхніх — типу немає.
# Півпальто сходить до пальта: окремого ключа ядра в осі теплової функції ніколи не було.
КОДИ_ВЕРХНЬОГО = frozenset({"coat", "half_coat", "trench_coat", "jacket", "vest", "cardigan", "down_jacket",
                            "fur_coat", "sheepskin_coat", "parka", "raincoat", "rain_cape", "windbreaker",
                            "anorak", "bomber", "poncho"})
_КОД_У_ТИП = {"half_coat": "coat"}
# Перелік типів верхнього — похідний від кодів, не окремий словник слів: ним звіряються споживачі.
ТИПИ_ВЕРХНЬОГО = tuple(dict.fromkeys(ВМ.ключ("item_type", _КОД_У_ТИП.get(к, к)) for к in sorted(КОДИ_ВЕРХНЬОГО)))
# Поля, які читають споживачі верхнього шару (`верхнє_пропорція`, `верхнє_погода`, `суд_погода`), а писача
# після рядка 5192 нема: їх дасть лише код моделі (етап 5192 «ознаки»). Доти запис каталогу їх не несе —
# «невідомо», і правило виходить питанням. Це назви полів запису (внутрішня мова), не слова з тексту.
ЗОВНІШНІ_ВХОДИ = {
 "ворс": "model code, row 5192; no writer until then",
 "капюшон_знімний": "model code, row 5192; no writer until then",
 "наповнювач": "model code, row 5192; no writer until then",
 "опушка": "model code, row 5192; no writer until then",
 "простібка_орієнтація": "model code, row 5192; no writer until then",
}
# ДОВЖИНА → РІВЕНЬ ТІЛА. ЗАЛИШЕНО ЛИШЕ ДЛЯ `фід_атрибути.довжина_речі` (інша сім'я рядка 5192 імпортує це
# ім'я): тут жоден шлях його вже не читає, видаляє його та сесія разом зі своїм читачем.
ДОВЖИНА_КЛЮЧІ = [
 ("максі",     ("максі", "макси", "в підлогу", "у підлогу", "довге пальто", "довгий пуховик")),
 ("литка",     ("міді", "по литк", "до литк", "нижче колін")),
 ("коліно",    ("до колін", "по колін", "на рівні колін")),
 ("стегно",    ("до стегн", "по стегн", "середин стегн", "півпальт", "полупальт",
                "укорочен", "вкорочен", "коротке пальто", "коротка")),
 ("талія",     ("кроп", "crop", "по талі", "до талі", "болеро")),
]


def верхні_атрибути(offer):
    """Атрибути верхнього шару КОДОМ: `{"тип_верхнього": ключ ядра}` або `{}`.

    `{}` — і для речі не верхнього шару, і коли код типу не з верхніх чи його нема. «Нема ключа»
    означає «невідомо», НЕ «нема»: на невідомому правило теми-11 виходить ПИТАННЯМ із названим
    блокером, на False — вердиктом, а мовчазний дефолт тут був би найдорожчою помилкою файлу.
    Крій, довжину, матеріал і візерунок кладе поверх запису збагачення (`накласти_форму`), оверсайз
    споживачі беруть із коду крою; решта ознак (бортність, пояс, комір, капюшон, опушка, простібка,
    ворс, наповнювач, склад, fill power) без коду моделі невідома. Дві осі рукава (крій пройми і довжина
    рукава) лишаються окремими полями запису: «довгий» не є ні регланом, ні вшивним.
    """
    сл = слот(offer)
    if сл != "верхній_шар" and "верхній_шар" not in (_альтернативні_слоти(offer, сл) if сл else ()):
        return {}
    пар = offer.get("параметри") or {}
    код = ВМ.код("item_type", str(пар.get("тип") or "").strip())
    if код not in КОДИ_ВЕРХНЬОГО:
        return {}
    return {"тип_верхнього": ВМ.ключ("item_type", _КОД_У_ТИП.get(код, код))}
