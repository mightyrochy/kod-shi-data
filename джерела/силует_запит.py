# ЧОГО БРАКУВАЛО. Все вище — ПЕРЕВІРКА зібраного образу: стиліст обрав речі, код каже,
# що не так, і віддає вікно на заміну. Це реактивний бік. Проактивний бік у системі був
# лише в кольорі: palette.розвилка_специфікацій віддає вікна L*/C*/дуги тону ДО того,
# як образ існує, і вони йдуть у фільтр фіду. По формі такого не було взагалі:
# ЦІЛЬ_ЛІТЕРИ читалась тільки з під_тіло() (перевірка), КРОЇ — тільки з ширина_крою()
# (теж перевірка). Тобто на питання «що шукати під цю фігуру» код не відповідав нічим.
#
# Тут той самий механізм обертається: замість «цей образ дав літеру X» — «на ЦЬОМУ тілі
# ось ці комбінації кроїв дають цільову літеру, ось вікна довжин у сантиметрах».
# Вихід — рядок у фільтр каталогу по полях `крій` і `довжина`, парний до колірного.

КРІЙ_СЛОТ = {
 "skinny": ("низ",), "straight": ("низ",), "tapered": ("низ",), "wide": ("низ",),
 "flared": ("низ",), "culottes": ("низ",), "pencil": ("низ",), "a-line": ("низ", "сукня"),
 "full": ("низ",), "pleated": ("низ",), "bias-slip": ("низ", "сукня"),
 "bodycon": ("верх", "сукня"), "fitted": ("верх", "верхній_шар"),
 "regular": ("верх", "верхній_шар"), "relaxed": ("верх", "верхній_шар"),
 "oversized": ("верх", "верхній_шар"), "belted": ("верх", "верхній_шар", "сукня"),
 "wrap": ("верх", "сукня"), "peplum": ("верх",), "shift": ("сукня",),
 "sheath": ("сукня", "верх"), "empire": ("сукня",),
 "double-breasted": ("верхній_шар",),
}

# Точки завершення, які реально бувають у каталозі, як частка від рівнів тіла.
# Це не вигадані числа: кожна — назва довжини з канонічного словника.
ДОВЖИНИ_ВЕРХУ = (("crop", "талія"), ("hip", "високе_стегно"), ("longline", "стегна"))
ДОВЖИНИ_НИЗУ = (("mini", "коліно"), ("knee", "коліно"), ("midi", "литка"),
                ("ankle", "щиколотка"), ("maxi", "щиколотка"))


# ── ЗАПОБІЖНИК: ЖОДЕН ЯРЛИК `fit.зони` НЕ ЛИШАЄТЬСЯ БЕЗ ЦІЛЬОВИХ ЛІТЕР ────────
# Список — звірка з гілками `ПС.зони` (fit.py, розділ «1. ТІЛО», функція `зони`:
# п'ять присвоєнь `ярлик = …`). Розрив між цими двома місцями вже стався один раз:
# «H/X межа» жила у `зони` й не мала ключа тут, і кожна комбінація кроїв на такому
# тілі діставала влучання 0 — простір порожній, бриф без силуетного блоку, а
# причина називалась «усі комбінації несуть блокер» при нулі блокерів. Мовчазної
# ціни в такого розриву нема: він гасить УВЕСЬ вихід модуля на цілому класі тіл,
# тому перевірка стоїть при імпорті, а не в тесті збоку.
_ЯРЛИКИ_FIT = {"A", "V", "X", "H", "H/X межа"}
assert _ЯРЛИКИ_FIT <= set(ЦІЛЬ_ЛІТЕРИ), (
    "ярлик fit.зони без цільових літер: %s" % (_ЯРЛИКИ_FIT - set(ЦІЛЬ_ЛІТЕРИ)))


def специфікація(t, intent="conventional", мета="лестити", пара=("верх", "низ")):
    """ЩО ШУКАТИ під це тіло: комбінації кроїв, що дають цільову літеру й не дають
    знахідок форми, з вікном довжини в сантиметрах під кожен слот.

    Це дзеркало palette.розвилка_специфікацій, тільки по осі форми, а не кольору.
    Нічого не ранжує: віддає ПРОСТІР законних варіантів (як і колірна розвилка),
    вибір за стилістом.

    ЧОГО ЦЕЙ ВИХІД НЕ ЗНАЄ І НЕ ВДАЄ:
      · нагода і формальність у крій не входять. Корпус зв'язує їх через ТИП виробу
        (олівець формальніший за карго), а типу в системі нема — це словник L2,
        окрема задача. Тому нагода лишається в сценарії (діапазон формальності + вето)
        і сюди не домішується: інакше вийшов би вигаданий місток;
      · тканина, рукав і виріз у формі не беруть участі;
      · довжини перевіряються тільки правилом краю (K-FIT-03), тобто «не на опуклості»,
        а не «доречно для цієї події».
    """
    верх_с, низ_с = пара
    Н = t["висоти"]
    кандидати_в = [k for k, s in КРІЙ_СЛОТ.items() if верх_с in s]
    кандидати_н = [k for k, s in КРІЙ_СЛОТ.items() if низ_с in s]
    ціль = ЦІЛЬ_ЛІТЕРИ.get(ПС.зони(t)["ярлик"], ((), ""))
    добрі, усі = [], 0
    for кв in кандидати_в:
        for назва_в, рів_в in ДОВЖИНИ_ВЕРХУ:
            for кн in кандидати_н:
                for назва_н, рів_н in ДОВЖИНИ_НИЗУ:
                    усі += 1
                    речі = [dict(id="верх", слот=верх_с, крій=кв,
                                 верх_см=Н["плечі"], низ_см=Н[рів_в]),
                            dict(id="низ", слот=низ_с, крій=кн,
                                 верх_см=Н["талія"], низ_см=Н[рів_н])]
                    об = обгортка(t, речі)
                    л = літера(об)
                    if not л["доступно"]: continue
                    складові = {л["тренд"], л["середина"]} - {"—"}
                    влучає = bool(складові & set(ціль[0]))
                    зн_форми = (конкуренція(t, об, intent) + об_єм(t, об, intent)
                                + зонні_операції(t, об, intent)
                                + нічия_стратегія(t, об, intent))
                    зн_краю = ПС.краї(t, речі, intent, мета)
                    if not (влучає and not зн_форми and not зн_краю): continue
                    добрі.append(dict(верх=dict(крій=кв, довжина=назва_в,
                                                поділ_см=round(Н[рів_в], 1)),
                                      низ=dict(крій=кн, довжина=назва_н,
                                               поділ_см=round(Н[рів_н], 1)),
                                      літера=л["літера"]))
    # згортка у ФІЛЬТР: які значення поля `крій` мають сенс на цьому тілі
    по_слотах = {}
    for слот, ключ in ((верх_с, "верх"), (низ_с, "низ")):
        крої_ = sorted({д[ключ]["крій"] for д in добрі})
        довж = sorted({д[ключ]["довжина"] for д in добрі})
        см = sorted({д[ключ]["поділ_см"] for д in добрі})
        по_слотах[слот] = dict(крій=крої_, довжина=довж,
                               поділ_від_підлоги_см=(min(см), max(см)) if см else None,
                               комбінацій=len(добрі))
    # ВЛАСНА РОЗДІЛЬНА ЗДАТНІСТЬ, порахована й віддана разом із виходом. Без цього
    # специфікація виглядає як фільтр, а поводиться як «майже все підходить»: на прогоні
    # трьох тіл (A/V/H) вона пропускала 34–42% простору, і списки кроїв для трьох різних
    # фігур збігались майже повністю. Причина названа й виміряна нижче: цільова літера
    # сліпне, щойно верх задає талію — X стоїть у цілях УСІХ типів корпусу, тож будь-який
    # приталений верх задовольняє тест незалежно від тіла, і низ лишається невільним.
    пари = {}
    for д in добрі: пари.setdefault(д["верх"]["крій"], set()).add(д["низ"]["крій"])
    усі_низи = set(кандидати_н)
    сліпі = sorted(k for k, v in пари.items() if len(v) >= 0.75 * len(усі_низи))
    return dict(тіло=ПС.зони(t)["ярлик"], цільові_літери=list(ціль[0]),
                роздільність=dict(
                    частка_законних=round(len(добрі) / max(1, усі), 3),
                    пар_крій_на_крій=sum(len(v) for v in пари.values()),
                    верхи_що_не_розрізняють=сліпі,
                    чому=("верх, що задає талію, дає літеру X, а X — цільова для A, V і H "
                          "одночасно: тест влучання проходить незалежно від фігури, і низ "
                          "лишається необмеженим. Розрізняє лише неструктурований верх "
                          "(oversized/regular/relaxed), де форму задає низ"),
                    що_полагодить=("порівняння обгортки з тілом ПО ЗОНАХ (K-BOD-00) "
                                   "замість згортки в одну літеру: літера не каже, ДЕ "
                                   "саме додано ширину, а анти-ходи корпусу — саме про це")),
                чому_ціль=ціль[1], intent=intent,
                перебрано=усі, законних=len(добрі),
                запит_у_фід=[dict(слот=с, **v) for с, v in по_слотах.items()],
                комбінації=добрі,
                не_знає=["нагода й формальність у крій не входять: корпус в'яже їх через "
                         "ТИП виробу, а типу в системі нема (словник L2 — окрема задача)",
                         "тканина, рукав і виріз у формі участі не беруть",
                         "довжини перевірені лише правилом краю, не доречністю до події",
                         "усі пороги під цим — T3, тому це простір варіантів, не рейтинг",
                         "розрізняє лише за неструктурованого верху — див. `роздільність`"])
