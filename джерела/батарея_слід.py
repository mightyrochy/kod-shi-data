#    контракті виходу (`протокол.py`: `"також_правила": список(РЯДОК)`) і доїжджає
#    до вердикту (`pipeline.py:1019`), тобто ID СТОЇТЬ У РЯДКУ, ЯКИЙ БАЧИТЬ
#    ЛЮДИНА. Не читати його означало карати правила за те, що система відмовилась
#    вимовляти той самий вимір двічі, — рівно та хвороба, від якої сімʼя силуету
#    вже відмовилась (K-SIL-01 злито з K-SIL-03).
#    ЧОМУ ОКРЕМИМ ЧИСЛОМ, А НЕ ТИХО В ЗАГАЛЬНОМУ. «Правило назвало себе на чужій
#    знахідці» — слабше твердження за «правило видало власний рядок»: суті в
#    нього своєї нема. Тому воно рахується, друкується окремим рядком і поіменно.
#
# 2. ЧЕКЛІСТ — ТРИСТАНОВИЙ, І «БЕЗ ВХОДУ» ТУТ НЕ МОВЧАННЯ. Чотири чеклісти
#    `суд_образу` (надлишок, прісність, палітра, аксесуари) ведуть кожен пункт зі
#    станом «провал / пройдено / без входу», з переліком своїх правил і з назвою
#    того, чого бракує. Це і є та форма, у якій корпус просить казати «правило
#    перевірено й не має входу» замість тиші (K-IO-04). Формою знахідки пункт не
#    є й бути не має: вироку над річчю в ньому нема, `суть` — нема, і
#    `знахідка.це_знахідка` його законно не бачить. Але ID у виході він НЕСЕ, і
#    правило, яке чесно вимкнене з названим полем, — це третій стан, а не мертве.
def знахідки_дерева(вихід):
    """(власні, спільні) — ID, названі у знахідках дерева.

    `власні` — поле `правило`: правило видало ВЛАСНИЙ рядок.
    `спільні` — поле `також_правила`: правило назвало себе на знахідці спільного
                механізму. Множини не перетинаються за побудовою: ID, що стоїть
                хоч раз власним, у `спільні` не повертається.
    """
    import знахідка as ЗН
    власні, спільні = set(), set()
    for _ш, з in ЗН.усі(вихід):
        if з.get("правило"):
            власні.add(з["правило"])
        for r in (з.get("також_правила") or ()):
            if r:
                спільні.add(str(r))
    return власні, спільні - власні


def чеклістні_дерева(вихід, корінь=""):
    """{ID: {стан, …}} — правила, названі пунктами тристанових чеклістів.

    Пункт розпізнається за ФОРМОЮ, а не за місцем, — з тієї самої причини, по
    якій так зроблено в `знахідка.усі`: перелік відер тут щоразу відставав би від
    коду. Форма пункта — `правила` плюс `стан`; форма рядка вердикту
    (`чекліст_вердикту`) — `правила` плюс `вимкнено`/`провал`.
    """
    out = {}

    def _додати(правила, стан):
        """Дописує `стан` кожному ID зі списку `правила`; порожні пропускає."""
        for r in (правила or ()):
            if r:
                out.setdefault(str(r), set()).add(стан)

    def обхід(в):
        """Рекурсивно обходить дерево виходу; пункт чекліста й бік вердикту впізнає за формою й глибше в них не заходить."""
        if isinstance(в, dict):
            # пункт `суд_образу.чеклісти`
            if "правила" in в and "стан" in в:
                _додати(в.get("правила"), str(в.get("стан")))
                return
            # бік `pipeline.чекліст_вердикту`
            if "правила" in в and ("вимкнено" in в or "провал" in в or "без_входу" in в):
                for п in (в.get("вимкнено") or []):
                    if isinstance(п, dict):
                        _додати(п.get("правила"), "без входу")
                _додати(в.get("правила"), "у чеклісті")
                return
            for v in в.values():
                обхід(v)
        elif isinstance(в, (list, tuple)):
            for v in в:
                обхід(v)

    обхід(вихід)
    return out
