def _рядки_другого_проходження(корп, знахідки, спільні, чекліст, у_сліді, мертві):
    """Реєстр `ДРУГЕ_ПРОХОДЖЕННЯ` проти ПРОГОНУ: що збіглось, що ні.

    ЧОМУ ЦЕ ДРУКУЄТЬСЯ, А НЕ ЛЕЖИТЬ ПОРУЧ. Двічі в цьому файлі вже стояв список,
    який ніщо не звіряло з кодом, і двічі він розійшовся мовчки: `ЦІЛІ_ОБРАЗІВ`
    зсунулись на елемент і сім рядків звіту стали на чужому доказі, а розкладка
    корпусу не сходилась із корпусом місяцями. Тому реєстр звіряється з тим
    самим прогоном, який дав числа вище, і розбіжність друкується ПОІМЕННО.

    ЩО САМЕ ЗВІРЯЄТЬСЯ — рівно те, що реєстр стверджує, і нічого понад:
      «а» і «б» → правило мусить ДОХОДИТИ до виходу в цьому прогоні (знахідкою,
                  полем `також_правила` або, для правил-процесів, слідом);
      «в»       → правило мусить бути НАЗВАНЕ як чесно вимкнене — пунктом
                  чекліста, записом `БЕЗ_ВХОДУ` або сусідньою знахідкою; його
                  мовчання лишається законним, безіменність — ні.
    Правило, яке реєстр числить розібраним, а прогін не дістає, стоїть у
    «⛔ РЕЄСТР РОЗІЙШОВСЯ З ПРОГОНОМ» — і це провал реєстру, не правила.
    """
    рядки, розбіжні, звірено = [], [], 0
    досяжні = set(знахідки) | set(спільні) | set(у_сліді)
    названі = досяжні | set(чекліст)
    поза = sorted(set(ДРУГЕ_ПРОХОДЖЕННЯ) - set(корп))
    за_літерою = {"а": [], "б": [], "в": []}
    for ід, (літ, доказ, чому) in sorted(ДРУГЕ_ПРОХОДЖЕННЯ.items()):
        за_літерою.setdefault(літ, []).append(ід)
        if ід in ПОЗА_БАТАРЕЄЮ:
            continue          # названий виняток, друкується окремо нижче
        звірено += 1
        ок = (ід in названі) if літ == "в" else (ід in досяжні)
        if not ок:
            розбіжні.append((ід, літ, доказ, чому))
    рядки.append("  ── ДРУГЕ ПРОХОДЖЕННЯ: (а)/(б)/(в) по кожному з %d ──"
                 % len(ДРУГЕ_ПРОХОДЖЕННЯ))
    рядки.append("  (а) батарея не мала умови правила:            %3d"
                 % len(за_літерою["а"]))
    рядки.append("  (б) правило діяло, ID у виході не стояв:      %3d"
                 % len(за_літерою["б"]))
    рядки.append("  (в) чесно вимкнене, поле названо:             %3d"
                 % len(за_літерою["в"]))
    if поза:
        рядки.append("  ⛔ ID реєстру, яких нема в корпусі (%d): %s"
                     % (len(поза), ", ".join(поза)))
    for ід, чому in sorted(ПОЗА_БАТАРЕЄЮ.items()):
        рядки.append("  ~ %-12s ПОЗА ЦІЄЮ БАТАРЕЄЮ: %s" % (ід, чому[:64]))
    if розбіжні:
        рядки.append("  ⛔ РЕЄСТР РОЗІЙШОВСЯ З ПРОГОНОМ (%d) — провал реєстру, не правил:"
                     % len(розбіжні))
        for ід, літ, доказ, чому in розбіжні:
            рядки.append("     (%s) %-12s проба %-22s %s" % (літ, ід, доказ, чому[:58]))
    else:
        # Число тут — ЗВІРЕНІ, а не всі: два записи `ПОЗА_БАТАРЕЄЮ` не звіряються
        # цим прогоном за побудовою, і писати їх у «✓» означало б зарахувати собі
        # перевірку, якої не було.
        рядки.append("  ✓ звірено %d із %d: кожен доходить до виходу або названий "
                     "вимкненим (решта — `ПОЗА_БАТАРЕЄЮ` вище)"
                     % (звірено, len(ДРУГЕ_ПРОХОДЖЕННЯ)))
    # Правило, яке прогін числить мертвим, а реєстр про нього мовчить: другий бік
    # тієї самої звірки. Без нього реєстр «повний» рівно доти, доки ніхто не
    # додав правила.
    без_рішення = sorted(set(мертві) - set(ДРУГЕ_ПРОХОДЖЕННЯ))
    if без_рішення:
        рядки.append("  ⚠ мертві БЕЗ рішення в реєстрі (%d): %s"
                     % (len(без_рішення), ", ".join(без_рішення[:14])))
    return рядки


def клас_сліду(ід):
    """Що правило винне виходу: «знахідка» | «слід» | «інфра».

    «знахідка» — мусить назвати себе у виході рядком, який людина або модель
                 може взяти й щось із ним зробити;
    «слід»     — правило-процес: іменований запис у точці спрацювання і є його
                 законним виходом (рішення вище, поіменно);
    «інфра»    — іменованого сліду не винне взагалі (`rule_genus.слід`).
    """
    import rule_genus as РР
    к = РР.слід(ід)
    if к != "знахідка":
        return к
    return "слід" if ід in СЛІД_ЗАКОННИЙ else "знахідка"


