def метал(offer, слот_=None):
    """Метал прикраси зі слова фіду. None, якщо слова нема — це НЕ «немає металу».

    ЧОМУ ЦЕ З'ЯВИЛОСЬ. Виміряно 29.08.2026: `outfit.метали` (K-COL-06-M) починається
    з `[e for e in E if e.get("метал")]` і мовчки виходить на порожньому списку. У
    каталозі — 0 речей із атрибутом металу з 7597. Тобто відповідь людини на
    елісітації («золото чи срібло біля обличчя») не мала з чим порівнюватись:
    правило звіряє названий метал із ПРОВІДНИМ металом образу, а образ металу не
    мав ніколи. Правило виконувалось і не міняло нічого.

    ЧОМУ ЛИШЕ ЮВЕЛІРНІ СЛОТИ. «Золотиста сукня» — це КОЛІР тканини, не метал біля
    обличчя, і K-COL-06-M на ній збрехав би. Так само «гольф … сталь» — назва
    відтінку. Обмеження слотами — не обережність, а те, про що правило: провідний
    метал рахується з `near` (приобличчева вага), і сенс має лише в прикрасах.
    Фурнітура сумок і взуття лишається невзятою: у повному каталозі слово
    «фурнітура» трапляється РАЗ, тобто джерела для неї у фіді просто нема.

    ПОКРИТТЯ, ЧЕСНО: 153 з 378 прикрас (40 %). Решта металу в тексті не називає —
    для них лишається None, і правило мовчить, як і мало б.
    """
    с = слот_ or слот(offer)
    if с not in _МЕТАЛ_СЛОТИ:
        return None
    т = " ".join(filter(None, [
        offer.get("назва") or "", offer.get("категорія") or "",
        " ".join("%s %s" % (k, v) for k, v in (offer.get("параметри") or {}).items())]))
    for ім, рег in _МЕТАЛ_РЕГ:
        if рег.search(т):
            return ім
    return None


def слот(offer, канал="жіноче"):
    """Слот речі. КАТЕГОРІЯ ПЕРЕВАЖУЄ НАЗВУ.

    `канал` — для кого цей прогін. Річ, що ЗАЯВЛЯЄ інший канал, слота не має;
    річ без заявленої статі судиться словником того самого каналу.

    ЧОМУ (знайдено 26.08.2026, вимір на дереві ager). Рядок склеювався як
    `категорія + назва`, і слово КРОЮ в назві важило стільки ж, скільки тип товару в
    категорії. Латентний доти, доки жоден ключ не збігався з назвою крою; став видимим
    при додаванні «бомбер» — тринадцять офферів
    `Женская одежда / Женские рубашки · «Рубашка-бомбер женская»` поїхали з «верх» у
    «верхній_шар», пул верху схуд, вершина композитора змінилась, §25 упав.

    ЦЕ НЕ ДУБЛЮЄ `ПАСТКИ_ПІДРЯДКА`, а доповнює її з іншого боку: пастка ловить ключ
    усередині ЧУЖОГО СЛОВА («кросбоді» ⊃ «боді») і працює навіть коли категорії нема;
    цей прохід ловить ключ у ЧУЖОМУ КРОЇ («сорочка-бомбер») і працює лише коли
    категорія щось каже. Перелічувати складені назви крою в пастках не можна — їх
    відкритий список («сукня-сорочка», «пальто-халат», «куртка-сорочка»).

    ДЕ ЛАМАЄТЬСЯ: магазин, що кладе товар у хибну категорію, тепер помиляється голосніше.
    Обмін усвідомлений: категорія — твердження продавця про товар, назва — маркетинг."""
    кат = (offer.get("категорія") or "").lower()
    # КАТЕГОРІЯ-АРТИКУЛ ВИМИКАЄТЬСЯ ТУТ, А НЕ НИЖЧЕ. Перша спроба глушила її лише
    # у проході по джерелах — і не спрацювала: `повний` склеює категорію з назвою,
    # а `_слот_у_тексті` бере ПЕРШИЙ слот за порядком словника, не за позицією в
    # рядку. «Шарф-35100» у складеному тексті все одно перемагав «Ремінь-35103».
    # Отруєний рядок треба не обходити, а не будувати.
    if _АРТИКУЛ_ЯК_КАТЕГОРІЯ.match(кат.rsplit(" / ", 1)[-1].strip()):
        кат = ""
    повний = f"{кат} {offer['назва']}".lower()
    # ── НЕ ЧАСТИНА ОБРАЗУ (28.08.2026) ───────────────────────────────────────
    # ФЕЙЛ-КЕЙС, стенд на каталог_brief під наміром statement: у слот «сумка» лягла
    # «Валіза SMART рожева» за 10 600 грн (категорія «сумки та валізи» ⊃ «сумк»), і
    # композитор поставив її в офісний образ. Валіза, гаманець, косметичка, чохол —
    # речі, які не вдягають; для них слота нема, і це названо.
    # лише за НАЗВОЮ: категорія «сумки та валізи» спільна для сумок і валіз, і за нею
    # без слота лишались 117 сумок (спіймано регресією одразу)
    _назва_l = str(offer.get("назва") or "").lower()
    if any(x in _назва_l for x in НЕ_ОДЯГ):
        return None
    # ЧУЖИЙ КАНАЛ. Є заявлена стать — вона вирішує, і словник не питається:
    # жниварка вже розклала речі по двох файлах, і файл є каналом. Нема
    # заявленої статі (старий каталог) — працює словник, як працював.
    # ── ЗАЯВЛЕНА СТАТЬ ВИРІШУВАЛА ЛИШЕ В ОДИН БІК (08.09.2026, крок A6) ──────
    # ЩО ЦЕ МІНЯЄ (правило 3). `канал_речі` рахувався і використовувався РІВНО як
    # прапорець «словник не питати». Тобто річ із `стать=чоловіче` не відсіювалась
    # НІЧИМ: словник її не бачив (бо стать заявлена), а з самим значенням ніхто
    # нічого не робив — порівняти його не було з чим, бо `слот()` не знала, який
    # канал просять. Заодно половина `НЕ_НАШ_КАНАЛ` («чоловіче») не читалась
    # ніколи.
    # ВИМІР на `каталог_повний`: усі 10 770 оферів заявляють `жіноче`, тож на
    # ЦЬОМУ каталозі поведінка не змінюється ні на одну річ — діра була латентна
    # й відкрилась би на першому змішаному фіді (а чоловічий каталог у проєкті
    # вже є). Тепер канал — параметр виклику з дефолтом «жіноче»: заявлений чужий
    # канал відсікається, незаявлений і «унісекс» лишаються, як лишались.
    _кан = канал_речі(offer)
    if _кан is not None:
        if _кан != канал:
            return None
    elif any(x in _назва_l for x in (НЕ_НАШ_КАНАЛ.get(канал) or ())):
        return None
    # ── ДІАЛЕКТ ЖНИВАРКИ: КАТЕГОРІЯ ВЖЕ Є ІМЕНЕМ СЛОТА (27.08.2026) ───────────
    # ФЕЙЛ-КЕЙС, каталог_повний.xml (7597 SKU, 46 магазинів): жниварка пише категорію
    # словником САМОГО проєкту («верх», «низ», «верхній_шар», «головний_убір») і
    # дублює її в param «слот». Ключі нижче шукають підрядки типу товару («блуз»,
    # «штан»), а не імена слотів, тож «верх» і «низ» не збігались НІ З ЧИМ — далі
    # слот вирішувало слово КРОЮ з назви («спідниця-сорочка» → верх), а 378 SKU
    # (263 верх · 84 низ · 11 верхній_шар · 20 головний_убір) не діставали слота
    # взагалі й випадали з каталогу. Це той самий клас дефекту, що вже стоїть у
    # пам'яті проєкту: імена полів збігаються, словник значень — ні.
    # Категорія-ім'я слота — твердження продавця, тож переважує назву, як і решта
    # категорій. Родина «прикраси» й тут дробиться на під-слоти ЗА НАЗВОЮ (сережки ≠
    # каблучка за приобличчевою вагою), інакше сім рядків SLOT_NEAR_FALLBACK знову
    # були б мертві.
    _лист = кат.rsplit(" / ", 1)[-1].strip()
    _оголош = (_лист if _лист in ІМЕНА_СЛОТІВ else
               ((offer.get("параметри") or {}).get("слот") or "").strip().lower())
    if _оголош in ІМЕНА_СЛОТІВ:
        if _оголош == "прикраси":
            for під, кл in ПІД_СЛОТИ_ПРИКРАС:
                if any(x in повний for x in кл):
                    return під
        return _оголош
    # КАТЕГОРІЯ-АРТИКУЛ НЕ Є КЛАСОМ РЕЧЕЙ (07.09.2026). Рядок виду «Шарф-35100»,
    # «Сукня-P29024PO» — назва ОДНОГО товару, і в новому фіді вона стоїть
    # категорією над іншими речами: «Шарф-35100» над «Ремінь-35103». Категорія
    # переважує назву за побудовою, тож ремінь ставав шарфом образу (136 речей).
    # Такий рядок не несе твердження про слот — вирішує назва.
    for джерело in (кат, повний):
        if not джерело:
            continue
        знайдено = _слот_у_тексті(джерело, повний)
        if знайдено is not None:
            return знайдено
    return None


# Імена слотів у словнику проєкту — рівно ті, що дає СЛОТ_КЛЮЧІ. Список виводиться,
# не переписується: новий слот у ключах автоматично стає розпізнаваним іменем.
ІМЕНА_СЛОТІВ = frozenset(с for с, _ in СЛОТ_КЛЮЧІ)


def _слот_у_тексті(текст, повний=None):
    """`текст` вирішує РОДИНУ слота, `повний` — члена родини.

    Розділення знайдено регресією: категорія «Прикраси» дає родину, але каблучку від
    сережок відрізняє лише НАЗВА. Прохід тільки по категорії повертав «прикраси» й
    обривав під-слоти, тобто відроджував сім мертвих рядків SLOT_NEAR_FALLBACK.
    Отже пріоритет категорії стосується вибору слота, а не деталізації всередині нього."""
    повний = текст if повний is None else повний
    for сл, ключі in СЛОТ_КЛЮЧІ:
        for k in ключі:
            if k not in текст:
                continue
            пастки = ПАСТКИ_ПІДРЯДКА.get(k)
            if пастки and any(p in текст for p in пастки):
                continue          # ключ є, але як частина чужого слова
            if сл == "прикраси":
                for під, кл in ПІД_СЛОТИ_ПРИКРАС:
                    if any(x in повний for x in кл):
                        return під
            return сл
    return None

# ── K-ACC-12: СЛОТ — НЕ ВЛАСТИВІСТЬ ТОВАРУ, А РІШЕННЯ КОМПОЗИТОРА ────────────
# ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after, тема-10 ЧАСТИНА XII.2 і ЧАСТИНА XX).
#   before — `слот()` повертає ОДИН слот на річ. Хустка 90×90 діставала «шарф»
#            назавжди, і правила приобличчевого поля застосовувались до неї навіть
#            тоді, коли фізично вона завʼязана на ручці сумки або на талії. Тобто
#            система рахувала приобличчевий колір речі, якої біля обличчя нема.
#   after  — річ несе МНОЖИНУ допустимих місць, а вибір місця стає окремим кроком зі
#            власним слідом. Той самий SKU на шиї, у волоссі, на плечах, на талії, на
#            сумці, на зап'ястку або ЯК ВЕРХ — це сім різних обʼєктів із різними
#            застосовними правилами.
#
# ЧОМУ ЦЕ НЕ «ЩЕ ОДНЕ ПРАВИЛО», А ЗМІНА КОНТРАКТУ: місце визначає, ЯКІ правила взагалі
# застосовуються. Хустка на шиї входить у приобличчеве поле (K-ACC-07) і в бюджет
# хроми біля обличчя; та сама хустка на талії викликає ПЕРЕДУМОВИ ПОЯСА (K-ACC-02:
# довжина торса й вираженість талії); на ручці сумки не чіпає ні того, ні іншого.
# Один слот на річ зробити це неможливо в принципі.
#
# ДЕ ЛАМАЄТЬСЯ: усі джерела трендових способів носіння — огляди сезонів SS'26/FW'26,
# тобто НАЙВИЩИЙ клас волатильності в корпусі (K-CRA-08, K-SYS-07). «Хустка як топ»
# може зникнути за сезон. Але САМА ВИМОГА множинного слота від тренду не залежить:
# вона випливає з того, що річ фізично може бути на семи місцях, і це було правдою й
# до 2026 року. Тому множина — `default`, а конкретні трендові місця — `hint`.
БАГАТОМІСНІ = {
 # слот-за-замовчуванням: (усі допустимі місця, чому саме ці)
 "шарф": (("шия", "волосся", "плечі", "талія", "сумка", "зап'ясток", "верх"),
          "квадрат фізично лягає на всі сім місць; які саме доступні — вирішує РОЗМІР "
          "(K-CRA-12: формат гейтить вузол), а не категорія товару"),
 "сумка": (("рука", "плече", "кросбоді"),
           "спосіб носіння міняє, чи зʼявляється край на торсі взагалі"),
}
# ПРИКРАС ТУТ НЕМА, І ЦЕ ВИПРАВЛЕННЯ ПЕРШОЇ ВЕРСІЇ. Проба показала, що «Каблучка
# срібна» діставала пʼять допустимих місць, включно з «шия» і «вухо» — а каблучка
# може бути лише на пальці. Багатомісність — властивість КОНКРЕТНОЇ речі (квадрат
# хустки справді лягає на сім місць; сумку справді носять трьома способами), а не
# цілого слота. Для прикрас правильна відповідь інша й вона вже є: ПІД_СЛОТИ_ПРИКРАС,
# де сережка й каблучка — різні речі з різною приобличчевою вагою.
# Місця, які НЕ входять у приобличчеве поле. Потрібні саме як заперечення: без цього
# списку будь-яка хустка тягла б за собою приобличчеві правила.
МІСЦЯ_ПОЗА_ОБЛИЧЧЯМ = ("талія", "сумка", "зап'ясток", "рука", "плече", "кросбоді",
                        "палець")


# ── ДВОСЛОТОВІ РЕЧІ: ІНШИЙ ВИМІР ТІЄЇ САМОЇ ІДЕЇ, ЩО K-ACC-12 ───────────────
# K-ACC-12 каже: МІСЦЕ речі на тілі — рішення композитора, не властивість товару.
# Тут те саме на рівень вище: у частини речей рішенням композитора є сам СЛОТ.
#
# ЗНАЙДЕНО ВИМІРОМ, не задумом. У дереві ager чотири категорії стабільно падали в
# «верх», хоча кожна з них у реальному образі буває верхнім шаром: кардигани (12 SKU
# у брифі), піджаки, жилети, болеро. Наряд теми 11 передбачив це з двох боків —
# «кардиган-як-верхній-шар» у межах теми, «не жакет і блейзер як частина костюма» поза.
#
# ЩО ЦЕ ЗНАЧИТЬ: кардиган сам по собі слота не має. Слот у нього зʼявляється, коли
# поруч стає пальто (тоді він «верх») або коли пальта нема, а надворі +12 (тоді він
# «верхній_шар»). `слот()` однозначна за побудовою і цього виразити не може.
#
# ЧОГО ЦЕ НЕ РОБИТЬ, І ЦЕ НАВМИСНО: не вирішує, ЯКИЙ слот узяти. Рішення за
# композитором — за температурою (K-WEA-01/02) і рештою образу. Тут лише перестає
# губитись сам факт двозначності: раніше кардиган мовчки був «верхом» і верхнім шаром
# бути не міг ніколи. Те саме мовчання, що K-ACC-12 знайшла для хустки на шиї.
ДВОСЛОТОВІ = [
 (("верх", "верхній_шар"), ("кардиган", "жакет", "піджак", "пиджак", "болеро", "жилет",
                            "кімоно", "кимоно", "пончо", "накидк", "кейп")),
]


def слоти(offer):
    """K-ACC-12. Множина допустимих місць речі. Порожня множина неможлива: якщо річ
    не багатомісна, множина — це її єдиний слот.

    Повертає dict(слот=..., місця=(...), місце=None, чому=...). `місце` лишається
    None НАВМИСНО: його ставить композитор, і поки він цього не зробив, жодне правило
    місця застосовувати не можна. Мовчазний дефолт «шия» повернув би стару помилку
    під новим імʼям."""
    с = слот(offer)
    if с is None:
        return dict(слот=None, місця=(), місце=None, слоти_альт=(),
                    чому="категорія не лягла в жоден слот")
    альт = _альтернативні_слоти(offer, с)
    if с not in БАГАТОМІСНІ:
        return dict(слот=с, місця=(с,), місце=с, слоти_альт=альт,
                    чому="річ одномісна: слот і місце збігаються"
                         + ("; слот, однак, двозначний — вибір за композитором" if альт else ""))
    місця, чому = БАГАТОМІСНІ[с]
    if с == "шарф":
        # ФОРМАТ ГЕЙТИТЬ МІСЦЕ (K-CRA-12), і ворота ФІЗИЧНІ: квадрата 70 см не
        # вистачає на повне обгортання голови, а 90 — вистачає. Це єдина частина
        # хусткового шару, що не є конвенцією.
        р = розмір_квадрата(offer)
        if р is not None and р < 90:
            місця = tuple(m for m in місця if m not in ("волосся", "верх", "плечі"))
            чому += "; формат %d см відсікає повне обгортання, плечі й «як верх»" % р
        return dict(слот=с, місця=місця, місце=None, розмір_см=р,
                    слоти_альт=альт, чому=чому)
    return dict(слот=с, місця=місця, місце=None, слоти_альт=альт, чому=чому)


def _альтернативні_слоти(offer, основний):
    """Слоти, крім основного, у яких річ теж може стояти. Порожньо — річ однослотова."""
    текст = f"{offer.get('категорія') or ''} {offer['назва']}".lower()
    for пара, ключі in ДВОСЛОТОВІ:
        if основний in пара and any(k in текст for k in ключі):
            return tuple(s for s in пара if s != основний)
    return ()


_РОЗМІР_РЕ = __import__("re").compile(r"(\d{2,3})\s*[хx×*]\s*(\d{2,3})")
def розмір_квадрата(offer):
    """Сторона квадрата зі назви/опису («90х90», «70x70»). None — не названо.
    Український роздріб дає це регулярно: 90×90 — стандартний лістинг."""
    т = f"{offer.get('назва','')} {offer.get('опис','') or ''}"
    м = _РОЗМІР_РЕ.search(т)
    if not м:
        return None
    a, b = int(м.group(1)), int(м.group(2))
    return min(a, b) if abs(a - b) <= max(a, b) * 0.25 else None

