# («100 % бавовна» → «вовна», «100 % поліестер» → «шовк»). Родина — мітка
# розділу магазину, не матеріал речі, і брати її тут означало б живити сольове
# вето вигадкою збирача.
# ЧОМУ РЯДОК ЯК Є, БЕЗ НОРМАЛІЗАЦІЇ В ОДИН ТЕРМІН: читачі шукають ОСНОВУ
# (`outer._основи` — від початку слова, `ВОЛОГІ_ВЕТО` — підрядком), і «50%
# Вовна, 30% Віскоза» віддає їм «вовн» без жодного словника. Нормалізація в
# один термін мусила б ОБРАТИ одне волокно з трьох — тобто вгадати частку, якої
# в рядку в 2/3 випадків не видно. Вузьке нормалізоване слово вже є окремо:
# `волокно` (V.волокно_зі_слова, найдовший корінь) — і саме тому воно тут не
# замінник: на «60% віскоза, 40% вовна» найдовший корінь віддає «віскоза», і
# вовна — та ознака, задля якої K-OUT-44 писалось, — зникає.
_МАТЕРІАЛ_КЛЮЧІ = ("склад", "~склад", "~матеріал", "~матеріал верху",
                   "~матеріал ззовні", "~склад тканини")


def матеріал_речі(offer):
    """(рядок складу в нижньому регістрі, за_чим) або (None, None).

    Перший ключ, що має значення, виграє: живе ім'я цього каталогу (`склад`,
    266 оферів brief) стоїть попереду діалектних (`~склад` 103, `~матеріал` 94,
    `~матеріал верху` 34). `матеріал_родина` СЮДИ НЕ ЙДЕ — див. блок вище."""
    пар = offer.get("параметри") or {}
    if not isinstance(пар, dict):
        return None, None
    for к in _МАТЕРІАЛ_КЛЮЧІ:
        v = str(пар.get(к) or "").strip().lower()
        if v:
            return v, ["param %s" % к]
    return None, None


# ── АТРИБУТИ ЗІ СТРУКТУРОВАНИХ PARAM (27.08.2026, каталог жниварки) ─────────
# ЩО ЦЕ МІНЯЄ (before/after, виміряно на 7597 SKU): шар слів читав ЛИШЕ назву.
# Жниварка кладе поруч крій (708 SKU), тканину (1895), принт (433), рукав (168),
# довжину (1233) і склад (83) окремими param — тим самим словником, що й наші
# словники слів. before: з_кроєм 489, з_тканиною 327, з_візерунком 320, довжина —
# нуль на всіх слотах, K-FIT-03 «утримано» в кожному образі. after: див. звіт
# прогону. Param — твердження продавця, тому йде ПОРУЧ із назвою, не замість неї:
# найдовший корінь усе одно виграє в тих самих функціях verify.
# ── ІМЕНА ПАРАМЕТРІВ ЖНИВАРКИ, А НЕ ВИГАДАНІ ─────────────────────────────
# ЗМІРЯНО 07.09.2026 на каталог_повний.xml (10 770 оферів, 43 магазини):
# чотири з семи ключів нижче НЕ ІСНУЮТЬ у жодному офері — «крій», «тканина»,
# «рукав», «матеріал». Жниварка пише «силует», «склад», «рукав_рівень»,
# «матеріал_верху». Тобто `слова_з_param` роками віддавала порожньо там, де
# магазин своє слово написав, а `крій`/`рукав` у картці для ші стояли 15 % / 0 %.
# Старі імена лишаються: вони нічого не коштують на діалекті, де їх нема, і
# ловлять фіди інших магазинів.
# ЧОГО ТУТ НЕМА І ЧОМУ:
#   · `матеріал_родина` (100 %) — розходиться зі «Складом» магазину в 57 %
#     (4 082 із 7 189), завжди в бік благороднішого волокна: «100 % бавовна» →
#     «вовна», «100 % поліестер» → «шовк». Це мітка розділу, не матеріал.
#   · `силует` (60 %) — 3 109 значень без джерела; вибірка дала вигадки
#     («створює акуратний силует» → футляр) і згрубіння (оверсайз → вільний).
#     Під'єднувати можна лише умовно (слово мусить стояти в тексті речі) —
#     це окрема правка з власним виміром, не ця.
#   · `утеплювач` — це наповнювач, не оболонка; у словесний шлях він занесе
#     «пух»/«перо» як волокно верху.
_PARAM_СЛОВА = ("крій", "тканина", "принт", "рукав", "склад", "матеріал", "довжина",
                # живі імена цього каталогу:
                "матеріал_верху", "рукав_рівень")
# «талія» СЮДИ НЕ ЙДЕ, хоч поле живе (624 офери). Її значення «на запах» довше за
# корінь «прям», а `крій_зі_слова` віддає перемогу НАЙДОВШОМУ кореню — тож
# «Нарядное платье ПРЯМОГО КРОЯ» з param «на запах» діставало крій `wrap` проти
# явного слова назви (виміряно: 40 речей, з них 3 перезаписи вже відомого крою).
# Це та сама механіка, що торік давала хибне волокно «за найдовшим коренем, а не
# за часткою». Талія — вісь обробки пояса, не вісь крою; щоб вона впливала на
# крій, потрібне правило пріоритету, а не збіг довжини рядка.

ДЕТАЛІ_КРОЮ = ("з розрізом", "корсетний", "на резинці", "сорочковий", "з басками",
               "з драпіруванням", "з запахом")


def _деталі_крою(offer):
    """Значення param «крій», які описують ДЕТАЛЬ, а не силует: поле `крій`
    (relaxed/straight/…) їх відкидає, і слово продавця гине. Список, не рядок.

    ⚠ НА ЦЬОМУ КАТАЛОЗІ ВХОДУ НЕМА (вимір 08.09.2026, крок аудиту A6). Коментар
    вище обіцяв «105 речей, які поле `крій` не приймало» — це число з фіду, де
    існував `param крій`. У `каталог_повний` такого параметра НЕМА в жодному з
    10 770 оферів (жниварка пише `силует`), і жодне зі значень `силует` не
    належить до `ДЕТАЛІ_КРОЮ`. Отже функція віддає порожній список на 100 %
    речей — і це не її дефект, а зникнення джерела.
    Не полагоджено підстановкою іншого поля навмисно: «з розрізом» і «корсетний»
    ніде більше у фіді не стоять, а виводити їх із назви означало б завести ще
    один здогад там, де раніше було слово продавця."""
    v = str((offer.get("параметри") or {}).get("крій") or "").strip().lower()
    return [v] if v in ДЕТАЛІ_КРОЮ else []


# ── `силует` ПІД'ЄДНАНО УМОВНО (08.09.2026, крок аудиту A6) ─────────────────
# Блок вище лишає цю правку відкритою словами: «Під'єднувати можна лише УМОВНО
# (слово мусить стояти в тексті речі) — це окрема правка з власним виміром, не
# ця». Вимір зроблено, і ось він (каталог_повний, 10 749 речей зі слотом):
#   крій зі слова, як було              1 407  (13 %)
#   `силует` мапиться в крій            5 107
#     · безумовно, речам БЕЗ крою      +3 811  → 5 218 (49 %), але 620 речей
#       дістали б крій, що СУПЕРЕЧИТЬ їхній власній назві
#     · умовно, слово в тексті речі    +1 354  → 2 761 (26 %), суперечностей 0
#       за побудовою (річ, у якої крій уже є зі слова, не чіпається)
# Умова — не обережність, а межа доказу: `силует_джерело` порожній у всіх 3 424
# випадках, де він є, а вибірка значень дала вигадки збирача («створює акуратний
# силует» → футляр). Коли слово стоїть у назві або описі САМОЇ речі, це слово
# магазину, а не здогад збирача, і його можна брати.
# Провенанс іде разом: `крій_за_чим` каже «param силует», щоб ніхто не сплутав
# це зі словом назви, і `крій_джерело` — щоб було видно, скільки крою в системі
# тримається на цьому шляху.
_СИЛУЕТ_У_КРІЙ = {"вільний": "relaxed", "прямий": "straight", "футляр": "sheath",
                  "приталений": "fitted", "а-силует": "a-line", "пишний": "full",
                  "на запах": "wrap"}


def крій_з_силуету(offer):
    """(крій, за_чим) з param «силует» — ЛИШЕ коли те саме слово стоїть у назві
    чи описі самої речі. Інакше (None, None): значення збирача без опори в тексті
    речі не є твердженням магазину."""
    v = str((offer.get("параметри") or {}).get("силует") or "").strip().lower()
    ц = _СИЛУЕТ_У_КРІЙ.get(v)
    if not ц:
        return None, None
    свій = "%s %s" % (offer.get("назва") or "", offer.get("опис") or "")
    if v not in свій.lower():
        return None, None
    return ц, ["param силует=«%s» (слово стоїть і в тексті речі)" % v]


def слова_з_param(offer):
    """Рядок зі значень структурованих param + список ключів, які його дали."""
    пар = offer.get("параметри") or {}
    взято = [k for k in _PARAM_СЛОВА if пар.get(k)]
    return " ".join(str(пар[k]) for k in взято), взято

# ДОВЖИНА ЗІ СЛОВА — ДЛЯ ВСІХ СЛОТІВ, НЕ ЛИШЕ ВЕРХНЬОГО ШАРУ. Рівень — слово
# каталогу → РІВЕНЬ ТІЛА (не сантиметр): у сантиметри його переводить композитор на
# профілі конкретної людини (той самий принцип, що ХАЛЯВА_ЗА_ТИПОМ). «міні» — свій
# рівень (середина стегна), бо «стегно» верхнього шару — це стегновий ОБХВАТ, куди
# міні-спідниця не сягає. Де ламається: «подовжена» і «вкорочена» — відносні слова,
# їх рівень залежить від слота, і поза верхом/верхнім шаром вони мовчать.
ДОВЖИНА_PARAM = {"міні": "міні", "міді": "литка", "максі": "максі", "до колін": "коліно",
                 "в підлогу": "максі", "до коліна": "коліно"}
ДОВЖИНА_КЛЮЧІ_ОДЯГ = [
 ("максі",  ("максі", "макси", "в підлогу", "у підлогу", "мідаксі")),
 ("литка",  ("міді", "по литк", "до литк", "нижче колін")),
 ("коліно", ("до колін", "по колін", "на рівні колін")),
 ("міні",   ("міні", "мини")),
 ("талія",  ("кроп", "crop", "укорочен", "вкорочен", "по талі", "до талі", "болеро")),
 ("стегно", ("подовжен", "удлинен", "по стегн", "до стегн")),
]
_ВІДНОСНІ_ЗА_СЛОТОМ = {("подовжена", "верх"): "стегно", ("вкорочена", "верх"): "талія",
                       ("вкорочена", "верхній_шар"): "стегно", ("подовжена", "верхній_шар"): "коліно"}

def довжина_речі(offer, сл):
    """(рівень, джерело) або (None, None). Param переважує назву (як категорія —
    назву): він походить із фасету/слага магазину, а назва буває обрізана."""
    # слова довжини — лише там, де є ПОДІЛ: «міні» на сумці — розмір, не край
    if сл not in ("сукня", "комплект", "низ", "верх", "верхній_шар"):
        return None, None
    пар = offer.get("параметри") or {}
    д = (пар.get("довжина") or "").strip().lower()
    if д:
        р = ДОВЖИНА_PARAM.get(д) or _ВІДНОСНІ_ЗА_СЛОТОМ.get((д, сл))
        if р and not (сл == "верх" and р in ("міні", "максі")):
            return р, "param довжина=«%s»" % д
    текст = ("%s %s" % (offer.get("категорія") or "", offer.get("назва") or "")).lower()
    ключі = ДОВЖИНА_КЛЮЧІ if сл == "верхній_шар" else ДОВЖИНА_КЛЮЧІ_ОДЯГ
    for р, кл in ключі:
        if any(k in текст for k in кл):
            if сл not in ("верх", "верхній_шар") and р in ("талія", "стегно"):
                continue                     # відносні слова поза верхом мовчать
            if сл == "верх" and р in ("міні", "максі"):
                continue                     # «міні» у верху — комплект зі спідницею, не край верху
            return р, "слово назви"
    return None, None


# ── R-PRN-07: РОЗМІЩЕННЯ МОТИВУ — ПОЛЕ, НЕ ДОДАТОК (27.08.2026) ──────────────
# Вартовий §18 упав на укр. каталозі: «Джинси прямі з вишивкою на кишені» (3 SKU) —
# слово розміщення поруч зі словом мотиву. Корпус (тема-1 §6.3): placed = створений
# фокус, що витрачає бюджет фокусу; border = точка завершення. Тут — лише читання
# поля; споживач — суд_образу.джерела_інтересу (placed → джерело інтересу). Де
# ламається: зона — слово каталогу («кишеня» → стегна), не вимір положення.
_РОЗМІЩЕННЯ_РЕ = __import__("re").compile(
    r"(принт|малюн|вишив|лого|напис|надпис|візерун|орнамент|аплікац)[а-яіїє']*\s+(на|по)\s+"
    r"(груд|спин|рукав|плеч|низ|подол|карман|кишен|поясі|талії)")
_ЗОНА_РОЗМІЩЕННЯ = {"груд": "груди", "спин": "спина", "рукав": "руки", "плеч": "плечі",
                    "карман": "стегна", "кишен": "стегна", "поясі": "талія", "талії": "талія",
                    "низ": "поділ", "подол": "поділ"}

def розміщення_мотиву(offer):
    """dict(вид='placed'|'border', зона=…, за_чим=…) або None."""
    м = _РОЗМІЩЕННЯ_РЕ.search((offer.get("назва") or "").lower())
    if not м: return None
    зона = _ЗОНА_РОЗМІЩЕННЯ.get(м.group(3))
    return dict(вид=("border" if зона == "поділ" else "placed"), зона=зона, за_чим=м.group(0))


def _злити_довжину(атр, дов):
    """Атрибути верхнього шару + рівень довжини (param > слово назви)."""
    a = dict(атр)
    if дов and дов[0]:
        a["довжина_рівень"], a["довжина_джерело"] = дов
    return a


# ── МАСШТАБ СУМКИ: ПОРЯДКОВА МІТКА МАГАЗИНУ, НЕ НАШЕ ЧИСЛО ──────────────────
# K-ACC-05 («масштаб аксесуара має ДВОБІЧНИЙ оптимум») вимагає рангу, а не сталої:
# джерело саме каже, що оптимум міряний У НАБОРІ кандидатів, і забороняє
# монотонну евристику «великій людині — велика сумка» в ОБИДВА боки.
# ВИМІРЯНО на `каталог_повний.xml` (476 сумок): порядкову мітку «формат»
# оголошують 58 карток (12.2 %) — «великий» 36, «середній» 18, «маленький» 4; ті
# самі картки несуть габарити «довжина N ширина N висота N» (57 шт.).
# Мітка береться ЯК Є й у сантиметри не переводиться: це ранг у власному ряду
# магазину, а перерахунок у нашу шкалу зробив би з чужого порядку наше число.
_ПРО_ФОРМАТ = re.compile(r"формат\s+(велик|середн|маленьк|мал)\w*")
_ФОРМАТ_СЛОВО = {"велик": "великий", "середн": "середній",
                 "маленьк": "маленький", "мал": "маленький"}


def сумкові_атрибути(offer):
    """Порядковий формат сумки зі слова картки. None — не названо, НЕ «середній»."""
    т = "%s %s %s" % (offer.get("категорія") or "", offer.get("назва") or "",
                      (offer.get("параметри") or {}).get("опис") or offer.get("опис") or "")
    м = _ПРО_ФОРМАТ.search(т.lower())
    return dict(формат=_ФОРМАТ_СЛОВО[м.group(1)]) if м else {}


# ── ДВІ ДОВЖИНИ, ЯКИХ НЕ ПИСАВ НІХТО, І ОБИДВІ Є В КАРТЦІ ───────────────────
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. `accessory.НОСІЇ_КРАЮ` читає `ремінь_см`, а
# `accessory.кольє_проти_горловини` — `ланцюг_см`. Обидва поля не писав НІХТО в
# усьому дереві: `feed` їх не рахував, тож на живому шляху K-EDG-01 діставало
# None на кожній сумці, а K-JEW-01 — на кожній прикрасі. Два правила про КРАЙ
# аксесуара (єдиний предмет теми-10 за її ж першою частиною) не виконувались
# жодного разу, і реєстр `БЕЗ_ВХОДУ["K-ACC-04"]` це чесно називав: «поле без
# постачальника».
# ВИМІРЯНО 17.09.2026 на `каталог_повний.xml` (10 770 оферів):
#   · сумки — `параметри["~ручка"]` несуть 177 карток із 476 (37.2 %); із них
#     149 довші за 40 см (плечовий/кросбоді ремінь) і 28 коротші (ручка в руку).
#     Ще 36 карток називають довжину ременя словами в описі.
#   · прикраси — `параметри["довжина_см"]` несуть 50 карток зі 104 (48.1 %),
#     значення 38–45 см; ще 53 картки називають довжину в тексті опису.
# ПАДІННЯ РЕМЕНЯ = ДОВЖИНА ÷ 2, І ЦЕ НЕ КОСМЕТИКА. Картка називає ПОВНУ довжину
# ременя (120, 115, 110 см — типові значення), а `НОСІЇ_КРАЮ["сумка"]` чекає
# `strap drop`: висоту, на яку сумка падає ВНИЗ від плеча. Ремінь, накинутий на
# плече, утворює замкнену петлю, тож падіння — половина довжини. Перевірка
# числом: 120 ÷ 2 = 60 см — рівно та європейська норма 55–60 см, яку коментар у
# `accessory._край_у_см` називає «правильною на 175 см і хибною на 158». Те саме
# ділення вже стоїть у `кольє_проти_горловини` для ланцюга, і з тієї ж причини.
# ДЕ ЛАМАЄТЬСЯ, І ЦЕ НАЗВАНО ТУТ, А НЕ ЗАМОВЧАНО: кросбоді носять ЧЕРЕЗ ТУЛУБ, і
# петля там не лежить на плечі — падіння в неї менше за половину, бо ремінь іде
# навскіс. Різниці ми не міряємо й не вигадуємо: для кросбоді число лишається
# половиною довжини, а `джерело_ременя` каже, звідки воно взялось, щоб читач
# виходу бачив припущення, а не голе число.
# КОРОТКА РУЧКА КРАЮ НА КОРПУСІ НЕ ДАЄ ВЗАГАЛІ: сумка в руці висить біля стегна
# на довжині РУКИ, а не ременя, і перетворювати 10 см ручки на «край на 163 см»
# означало б порахувати правило на речі, до якої воно не застосовне. Поріг 40 см
# — половина найкоротшого плечового ременя каталогу (80 см), тобто межа між
# двома способами носіння, а не наша шкала.
_РУЧКА_МІН_СМ = 40.0
_ПРО_РЕМІНЬ = re.compile(
    r"(?:ремін|ремеш|ручк|лямк|плечов)\w*[^.;\n]{0,40}?(\d{2,3})(?:[,.]\d+)?\s*(?:см|cм|cm)", re.I)
_ПРО_ЛАНЦЮГ = re.compile(
    r"(?:довжин|ланцюж|ланцюг|цепочк)\w*[^.;\n]{0,30}?(\d{2,3})(?:[,.]\d+)?\s*(?:см|cм|cm)", re.I)
_ЧИСЛО_ПОЛЯ = re.compile(r"^\s*(\d{1,3})(?:[,.]\d+)?\s*(?:см|cм|cm)?\s*$", re.I)
_ЛАНЦЮГ_СЛОТИ = ("прикраси", "кольє", "намисто")


def _число_з_поля(знач):
    """Значення param → число в см, або None. Картка пише і «120», і «14 см», і «17 cм»
    (з ЛАТИНСЬКОЮ `c`) — три написання одного числа, і кожне зустрічається."""
    if знач in (None, ""):
        return None
    м = _ЧИСЛО_ПОЛЯ.match(str(знач))
    return float(м.group(1)) if м else None


def аксесуарні_довжини(offer, сл):
    """`ремінь_см` (падіння ременя сумки) і `ланцюг_см` (довжина ланцюга прикраси).

    Порядок джерел той самий, що всюди у файлі: ПОЛЕ картки переважує слово тексту —
    поле це твердження продавця, слово це наш здогад про його фразу. `*_джерело`
    їде поруч із числом, бо припущення «падіння = довжина ÷ 2» мусить бути видне
    там, де його читають, а не лише тут."""
    пар = offer.get("параметри") or {}
    if сл == "сумка":
        повна = _число_з_поля(пар.get("~ручка"))
        джерело = "поле картки «ручка»"
        if повна is None:
            т = "%s %s" % (offer.get("назва") or "", пар.get("опис") or offer.get("опис") or "")
            м = _ПРО_РЕМІНЬ.search(т)
            повна, джерело = (float(м.group(1)), "слово опису") if м else (None, None)
        if повна is None or повна < _РУЧКА_МІН_СМ:
            return {}
        return dict(ремінь_см=round(повна / 2.0, 1),
                    ремінь_джерело="%s: повна довжина %g см, падіння = половина петлі"
                                   % (джерело, повна))
    if сл in _ЛАНЦЮГ_СЛОТИ:
        дов = _число_з_поля(пар.get("довжина_см"))
        джерело = "поле картки «довжина_см»"
        if дов is None:
            т = "%s %s" % (offer.get("назва") or "", пар.get("опис") or offer.get("опис") or "")
            м = _ПРО_ЛАНЦЮГ.search(т)
            дов, джерело = (float(м.group(1)), "слово опису") if м else (None, None)
        if дов is None:
            return {}
        return dict(ланцюг_см=дов, ланцюг_джерело=джерело)
    return {}


def панчішні_атрибути(offer):
    """DEN зі назви. Українські фіди це поле реально несуть — тому K-HOS-01 має
    вхід одразу, на відміну від більшості теми-10."""
    м = _ПРО_DEN.search(f"{offer.get('назва','')} {offer.get('опис','') or ''}")
    return dict(den=int(м.group(1))) if м else {}


_МЕТАЛ_СЛОТИ = {"сережки", "кольє", "намисто", "браслет", "каблучка",
                "прикраси", "підвіска", "брошка"}
# ── ФУРНІТУРА — НОСІЙ МЕТАЛУ НАРІВНІ З ПРИКРАСОЮ (K-ACC-03), АЛЕ ЛИШЕ З ПОЛЯ ──
# K-ACC-03 дослівно: «the same rule as K-CRA-07 (metal consistency), because this
# is the same rule with a wider set of carriers», і носіями названо пряжку пояса
# й фурнітуру сумки. Блокер під правилом каже «0 із 260 назв ager несуть слово про
# метал» — вимір ОДНОГО каталогу 26.08.2026. На `каталог_повний` (10 770 оферів)
# поле `параметри["метал"]` стоїть на 25 речах ПОЗА ювелірними слотами: пояс 23
# (срібло 14, золото 7, латунь 2) і брошка 2 (золото).
# ЧОМУ ФУРНІТУРА БЕРЕТЬСЯ ЛИШЕ З ПОЛЯ, А НЕ З НАЗВИ. Докстрінг `метал` нижче
# пояснює, чому назва звужена до прикрас: «золотиста сукня» — це КОЛІР тканини,
# і K-COL-06-M (провідний метал біля обличчя) на ній збрехав би. Поле `метал` —
# твердження продавця про матеріал, а не слово про відтінок, тож із нього фурнітура
# читається безпечно. Тому слоти розведено: назва — `_МЕТАЛ_СЛОТИ`, поле —
# `_МЕТАЛ_СЛОТИ | _МЕТАЛ_СЛОТИ_ПОЛЕ`.
_МЕТАЛ_СЛОТИ_ПОЛЕ = {"пояс", "сумка"}
_МЕТАЛ_РЕГ = (
    ("золото", re.compile(r"золот|позолот|gold", re.I)),
    ("срібло", re.compile(r"срібл|посрібл|silver", re.I)),
)
# ── СЛОВНИК МЕТАЛІВ — ТОЙ САМИЙ, ЩО В СУДІ (17.09.2026) ─────────────────────
# ЩО ЦЕ МІНЯЄ. `суд_образу` знає шість металів (МЕТАЛИ_ТЕПЛІ = золото, бронза,
# латунь, мідь; МЕТАЛИ_ХОЛОДНІ = срібло, біле_золото, платина, сталь), а сюди
# доїжджали рівно два. Каталог при цьому пише в `параметри["метал"]` ще `сталь`
# (15 речей) і `латунь` (2): фід називає метал тим самим словом, яким його називає
# суд, а перекладач між ними знав два слова з шести. Наслідок для K-CRA-07 («мікс
# без повтору») прямий: сталевий браслет при золотих сережках — це ДВА тони, і
# правило мусить їх побачити; доти сталь просто не існувала, і мікс виглядав
# однотонним.
_ПОЛЕ_МЕТАЛУ = ("метал", "~метал", "~матеріал", "~матеріал верху")
_МЕТАЛ_СЛОВНИК = ("золото", "срібло", "сталь", "латунь", "бронза", "мідь",
                  "платина", "біле_золото")


def метал(offer, слот_=None):
    """Метал прикраси зі слова фіду. None, якщо слова нема — це НЕ «немає металу».

    ЧОМУ ЦЕ З'ЯВИЛОСЬ. Виміряно 29.08.2026: `суд_образу.метали` (K-COL-06-M) починається
    з `[e for e in E if e.get("метал")]` і мовчки виходить на порожньому списку. У
    каталозі — 0 речей із атрибутом металу з 7597. Тобто відповідь людини на
    елісітації («золото чи срібло біля обличчя») не мала з чим порівнюватись:
    правило звіряє названий метал із ПРОВІДНИМ металом образу, а образ металу не
    мав ніколи. Правило виконувалось і не міняло нічого.

    ЧОМУ ЛИШЕ ЮВЕЛІРНІ СЛОТИ. «Золотиста сукня» — це КОЛІР тканини, не метал біля
    обличчя, і K-COL-06-M на ній збрехав би. Так само «гольф … сталь» — назва
    відтінку. Обмеження слотами — не обережність, а те, про що правило: провідний
    метал рахується з `near` (приобличчева вага), і сенс має лише в прикрасах.
    Фурнітура сумок і взуття лишається невзятою: у повному каталозі слово
    «фурнітура» трапляється РАЗ, тобто джерела для неї у фіді просто нема.

    ПОКРИТТЯ, ЧЕСНО: 153 з 378 прикрас (40 %). Решта металу в тексті не називає —
    для них лишається None, і правило мовчить, як і мало б.

    ── ПОЛЕ ФІДУ ЧИТАЄТЬСЯ ПЕРШИМ І ЦІЛИМ СЛОВНИКОМ (17.09.2026, K-CRA-07) ──
    ЩО ЦЕ МІНЯЄ В РІШЕННІ (виміряно на `каталог_повний`, 10 770 оферів).
      before — метал шукався ДВОМА регулярками (золото / срібло) у склеєному рядку
               «назва + категорія + усі параметри». Каталог при цьому пише метал
               ОКРЕМИМ полем `параметри["метал"]` на 60 речах, і словник того поля
               ширший за дві регулярки: сталь 15, латунь 2. Сталь із `прикраси`
               доїжджала лише випадково — коли в тій самій картці десь стояло слово
               «золото» (позолочене кріплення), тобто правило діставало ХИБНИЙ тон.
      after  — поле читається першим і звіряється зі словником, який уже знає
               `суд_образу` (МЕТАЛИ_ТЕПЛІ + МЕТАЛИ_ХОЛОДНІ). Назва лишається другим
               джерелом і далі звужена до прикрас.
    Носії: ювелірні слоти читаються обома джерелами; пояс і сумка (K-ACC-03:
    «the same rule with a wider set of carriers») — ЛИШЕ полем. Це +25 речей
    (пояс 23, брошка 2), яких K-CRA-07 не бачив жодного разу.
    """
    с = слот_ or слот(offer)
    з_поля = _метал_з_поля(offer)
    if з_поля and с in (_МЕТАЛ_СЛОТИ | _МЕТАЛ_СЛОТИ_ПОЛЕ):
        return з_поля
    if с not in _МЕТАЛ_СЛОТИ:
        return None
    т = " ".join(filter(None, [
        offer.get("назва") or "", offer.get("категорія") or "",
        " ".join("%s %s" % (k, v) for k, v in (offer.get("параметри") or {}).items())]))
    for ім, рег in _МЕТАЛ_РЕГ:
        if рег.search(т):
            return ім
    return None


def _метал_з_поля(offer):
    """Метал із ОГОЛОШЕНОГО поля картки, звірений зі словником суду. None — поля нема.

    Звірка потрібна, бо поле вільне: «метал: сталь+емаль» має віддати «сталь», а
    «метал: ювелірний сплав» — нічого. Підставляти сусіднє слово тут не можна з тієї
    самої причини, з якої `паспорт_з_json` не підставляє реєстр: вигаданий вхід
    невідрізненний від виміряного."""
    п = offer.get("параметри") or {}
    for ключ in _ПОЛЕ_МЕТАЛУ:
        v = str(п.get(ключ) or "").strip().lower()
        if not v:
            continue
        for ім in _МЕТАЛ_СЛОВНИК:
            if ім.replace("_", " ") in v or ім in v:
                return ім
    return None

# ═══════════════ 3. КОЛІР РЕЧІ З ФОТО ═══════════════
ФОН = dict(L=90.0, C=8.0)      # T3: майже біле й ненасичене в товарному фото — тло

def _зразок_пікселів(джерело, центр=0.55, макс_сторона=400, timeout=15):
    """Спільна підготовка: кроп центру -> відкидання тла/бліків/тіней.
    Повертає (rgb_dict, діаг) або (None, діаг), якщо після відкидання лишилось <10%.
    Виділено з колір_з_фото, щоб екстракція палітри принту йшла ТИМ САМИМ
    відкиданням, а не паралельним — інакше два шляхи розійдуться на тлі/бліках."""
    from PIL import Image
    if str(джерело).startswith("http"):
        import requests
        r = requests.get(джерело, timeout=timeout); r.raise_for_status()
        im = Image.open(io.BytesIO(r.content))
    else:
        im = Image.open(джерело)
    im = im.convert("RGB")
    im.thumbnail((макс_сторона, макс_сторона))
    W, Hh = im.size
    x0, y0 = int(W*(1-центр)/2), int(Hh*(1-центр)/2)
    box = im.crop((x0, y0, W-x0, Hh-y0))
    px = {(x, y): box.getpixel((x, y)) for y in range(box.size[1]) for x in range(box.size[0])}
    всі = len(px)
    # ВАЖЛИВО: фільтри працюють у Lab, а кластеризатор чекає RGB і сам кличе to_lab.
    # Подвійне перетворення робило кемел (L*66) чорним (L*12) — тягнемо ключ, не Lab.
    трійки = [(k, to_lab(v), v) for k, v in px.items()]
    не_тло = [t for t in трійки if not (t[1][0] >= ФОН["L"] and lch(t[1])[1] <= ФОН["C"])]
    діаг = dict(пікселів=всі, тло=всі-len(не_тло))
    if len(не_тло) < 0.10*всі:
        return None, dict(діаг, причина="після відкидання тла лишилось <10% — "
                                        "ймовірно фото на білому з дрібним товаром")
    labs_ok, n_sp = reject_specular([t[1] for t in не_тло])
    набір = {id(l) for l in labs_ok}
    не_тло = [t for t in не_тло if id(t[1]) in набір]
    labs_ok, n_sh = reject_shadow([t[1] for t in не_тло])
    набір = {id(l) for l in labs_ok}
    не_тло = [t for t in не_тло if id(t[1]) in набір]
    діаг.update(блиск=n_sp, тінь=n_sh)
    return {t[0]: t[2] for t in не_тло}, діаг


def колір_з_фото(джерело, центр=0.55, макс_сторона=400, timeout=15):
    """Домінанта центральної зони після відкидання тла, бліків і тіней.
    Повертає (lab, впевненість, діагностика). Впевненість низька, якщо після
    відкидання лишилось мало пікселів або якщо кластерів кілька зі схожими
    частками — тоді це принт або фото на моделі, і колір речі не визначений."""
    rgb, діаг = _зразок_пікселів(джерело, центр, макс_сторона, timeout)
    if rgb is None:
        return None, 0.0, діаг
    кластери, шум = areas.кольори(rgb, list(rgb), мін_частка=0.08)
    діаг["кластерів"] = len(кластери)
    домінанта = кластери[0]
    # РОЗКИД ДОМІНАНТИ — не константа, а вимір. Єдине число, яке можна відкалібрувати
    # без розмітки: прогін по фіду дає, наскільки стабільний колір речі на фото.
    # Далі воно їде в реєстр_правил._сила як точність входу.
    свої = [l for l in (to_lab(rgb[k]) for k in rgb)
            if de00(l, домінанта["lab"]) <= 12.0]
    st_ = zone_stats(свої) if len(свої) >= 20 else None
    домінанта["розкид"] = st_["spread"] if st_ else None
    впевненість = round(домінанта["частка"], 2)
    if len(кластери) > 1 and кластери[1]["частка"] > 0.6*домінанта["частка"]:
        впевненість *= 0.5
        діаг["причина"] = "два співмірні кластери — принт, фото на моделі або двоколірна річ"
    діаг["розкид"] = домінанта["розкид"]
    return домінанта["lab"], round(впевненість, 2), діаг


# ═══════════════ 3b. ВНУТРІШНЯ ПАЛІТРА ПРИНТУ (напрям A, garment-side) ═══════════════
РОЛІ_ПОРЯДОК = ("домінанта", "секундант", "акцент")
ПРИНТ_МІН_ЧАСТКА = 0.06   # T3: кластер дрібніший — фактура/нитка, не колірна роль
ПРИНТ_ПОРІГ_ВПЕВНЕНОСТІ = 0.55   # T3: нижча впевненість домінанти -> міряти як принт
# Порогів гучності НЕМА: гучність принту неперервна (див. _гучність_принту).
# «3-color rule» лишається у фольклорі, а не як обрив у коді.

def _просторові_міри(rgb, кластери):
    """РЕАЛЬНИЙ ВИМІР (не заглушка). Раніше я писав «масштаб не вимірюється,
    color-only» — це було хибно: ключі пікселів несуть координати (x,y), тобто
    просторова сітка вже в руках. Тут з неї беруться три величини:

      масштаб_відн  — медіанна довжина пробігу мотиву вздовж рядків/стовпців,
                      поділена на ширину кадру речі. 0.02 = дрібний ситець,
                      0.35 = великий мотив. ВІДНОСНО КАДРУ, не в см: кроп
                      каталожного фото невідомий, тому абсолютний розмір
                      недосяжний, а відносний — придатний і калібрований далі.
      чіткість_краю — частка переходів між сусідніми пікселями з великим ΔE
                      серед усіх переходів (Raes: «clarity of edge»: чіткий
                      горох проти washy пастелі).
      ґрунт         — частка найбільшого кластера (є де оку відпочити).

    Стеля: JPEG-артефакти й дрібна текстура тканини роздрібнюють пробіги, тому
    пробіги в 1–2 пікселі відкидаються; на дуже дрібному принті вимір занижений.
    Мотиву як ФОРМИ (рух: круглий/лінійний) це не дає — то лишається за VLM."""
    if not rgb or not кластери:
        return dict(масштаб_відн=None, чіткість_краю=None, ґрунт=None)
    if len(кластери) < 2:
        # однотонна річ: мотиву немає, отже масштаб не «величезний», а НЕВИЗНАЧЕНИЙ.
        return dict(масштаб_відн=None, чіткість_краю=None, ґрунт=1.0)
    центри = [c["lab"] for c in кластери]
    мітка = {}
    for k, v in rgb.items():
        lab = to_lab(v)
        мітка[k] = min(range(len(центри)), key=lambda i: de00(центри[i], lab))
    xs = [k[0] for k in rgb]; ys = [k[1] for k in rgb]
    W = max(xs) - min(xs) + 1; H = max(ys) - min(ys) + 1
    пробіги = []
    for вісь in (0, 1):
        лінії = defaultdict(list)
        for k in rgb:
            лінії[k[1] if вісь == 0 else k[0]].append(k)
        for ключ, точки in лінії.items():
            точки.sort(key=lambda p: p[0] if вісь == 0 else p[1])
            довж, попер = 0, None
            for p in точки:
                m = мітка[p]
                if m == попер:
                    довж += 1
                else:
                    if попер is not None and довж > 2: пробіги.append(довж)
                    довж, попер = 1, m
            if попер is not None and довж > 2: пробіги.append(довж)
    масштаб = (statistics.median(пробіги) / max(W, H)) if пробіги else None
    # чіткість краю (Raes «clarity of edge»): різкість САМЕ НА МЕЖАХ мотиву.
    # Частка різких переходів серед УСІХ пар міряла б периметр мотиву, не різкість,
    # тому беремо середній ΔE лише на парах, де мітка кластера змінюється:
    # washy-градієнт дає малий крок на межі, чіткий горох — великий.
    межові = []
    for (x, y), v in rgb.items():
        for dx, dy in ((1, 0), (0, 1)):
            сусід = rgb.get((x+dx, y+dy))
            if сусід is None: continue
            if мітка[(x, y)] != мітка[(x+dx, y+dy)]:
                межові.append(de00(to_lab(v), to_lab(сусід)))
    чіткість = min(1.0, statistics.mean(межові) / 25.0) if межові else None   # T3 нормування
    ґрунт = кластери[0]["частка"] / sum(c["частка"] for c in кластери)
    return dict(масштаб_відн=round(масштаб, 3) if масштаб else None,
                чіткість_краю=round(чіткість, 3) if чіткість is not None else None,
                ґрунт=round(ґрунт, 3))


def _гучність_принту(кольорові, контраст, масштаб_відн=None):
    """Неперервна самовідносна сила властивості (калібрування не треба): 0 = тихий
    принт (домінанта тримає поле, низький контраст, мало кольорів, приглушено),
    1 = гучний (рівні частки без ґрунту, високий контраст, багато яскравих кольорів).
    Складові підтверджені практиками: КОНТРАСТ (Lamport: вищий контраст читається
    гучніше й «більше»), ЩІЛЬНІСТЬ/брак ґрунту (Raes/Lamport: рівний розподіл без
    домінантного поля — «нема де оку відпочити»), кількість кольорів, хрома, і
    МАСШТАБ мотиву (Lamport/ctnbee: великий мотив читається гучніше) — останній
    входить ЛИШЕ коли виміряний; за відсутності ваги перенормовуються, щоб
    відсутність виміру не зсувала гучність тихцем. Усі нормування T3 некалібровані;
    це НЕ надійність виміру (та — окремо, `впевненість`)."""
    if not кольорові:
        return 0.0
    n = len(кольорові)
    частки = sorted((c["частка"] for c in кольорові), reverse=True)
    ground = частки[0] / sum(частки)                         # частка домінанти серед кольорових
    t_контраст  = min(1.0, (контраст or 0.0) / 55.0)         # T3: ΔL≈55 -> гучно
    t_щільність = min(1.0, max(0.0, (1.0 - ground) / 0.60))  # T3: ground<0.40 -> максимум
    t_кількість = min(1.0, (n - 1) / 3.0)                    # T3: 1 колір=0, 4+=1
    t_хрома     = min(1.0, (sum(lch(c["lab"])[1] for c in кольорові) / n) / 60.0)  # T3
    складові = [(0.30, t_контраст), (0.26, t_щільність),
                (0.16, t_кількість), (0.16, t_хрома)]
    if масштаб_відн is not None:
        складові.append((0.12, min(1.0, масштаб_відн / 0.25)))   # T3: 0.25 ширини -> великий
    W = sum(w for w, _ in складові)
    return sum(w*t for w, t in складові) / W

def палітра_принту(джерело, центр=0.55, макс_сторона=400, timeout=15):
    """Напрям A. Внутрішня палітра ПРИНТОВАНОЇ речі з фото каталогу. Той самий
    відкидач тла/бліків/тіней, що й колір_з_фото, але кластери НЕ згортаються до
    домінанти — кожен стає роллю за часткою (Тайх/Штольцфус: «принт несе кілька
    кольорів; витягни й повтори деінде»).

    ЧЕСНА СТЕЛЯ (докстрінг модуля): цей шлях НЕ відрізняє справжній принт від
    фото-на-моделі чи флетлея з реквізитом. Тому впевненість НИЗЬКА за конструкцією
    — це підказка композитору, не виміряна істина. Масштаб мотиву тут НЕ вимірюється
    (color-only): віддаємо внутрішній КОНТРАСТ (ΔL), не розмір.

    Нейтралі принту йдуть окремим списком `нитки` — судить їх ОДНЕ визначення
    нейтралі системи (колір_образу.нейтраль), а не сирий поріг C*. Розвилка «нейтраль =
    колір?» вирішується вже в palette.роль_принту.

    Повертає dict(ролі, нитки, гучність, n_кольорів, контраст, масштаб_відн,
    чіткість_краю, ґрунт, впевненість, діаг)."""
    rgb, діаг = _зразок_пікселів(джерело, центр, макс_сторона, timeout)
    if rgb is None:
        return dict(ролі=[], нитки=[], гучність=0.0, n_кольорів=0, контраст=None,
                    масштаб_відн=None, чіткість_краю=None, ґрунт=None,
                    впевненість=0.0, діаг=діаг)
    кластери, шум = areas.кольори(rgb, list(rgb), мін_частка=ПРИНТ_МІН_ЧАСТКА)
    діаг["шум_частка"] = шум
    def оформити(c, роль):
        L, C, h = lch(c["lab"])
        return dict(роль=роль, lab=list(c["lab"]), частка=c["частка"],
                    L=round(L, 1), C=round(C, 1), h=round(h, 1))
    кольорові = [c for c in кластери if нейтраль(c["lab"]) is None]
    нейтральні = [c for c in кластери if нейтраль(c["lab"]) is not None]
    ролі = [оформити(c, r) for c, r in zip(кольорові[:3], РОЛІ_ПОРЯДОК)]
    нитки = [оформити(c, "нитка") for c in нейтральні]
    Ls = [r["L"] for r in ролі]
    if len(Ls) < 2:
        Ls = [lch(c["lab"])[0] for c in кластери]     # запасне: усі кластери
    контраст = round(max(Ls) - min(Ls), 1) if len(Ls) >= 2 else 0.0
    прост = _просторові_міри(rgb, кластери)
    гучність = _гучність_принту(кольорові, контраст, прост["масштаб_відн"])
    впевненість = 0.35
    if len(кластери) >= 2 and кластери[1]["частка"] > 0.6*кластери[0]["частка"]:
        впевненість = 0.25
        діаг["причина"] = "співмірні кластери — принт / фото на моделі / двоколірна річ"
    return dict(ролі=ролі, нитки=нитки, гучність=round(гучність, 2),
                n_кольорів=len(кольорові), контраст=контраст,
                масштаб_відн=прост["масштаб_відн"], чіткість_краю=прост["чіткість_краю"],
                ґрунт=прост["ґрунт"], впевненість=round(впевненість, 2), діаг=діаг)

# ═══════════════ 4. ПОКРИТТЯ ВІКОН ═══════════════
def підходить(lab, запит):
    L, C, h = lch(lab)
    if not (запит["L_min"] <= L <= запит["L_max"]): return False
    # ── ВИКЛЮЧЕНА КУЛЯ ЧИТАЄТЬСЯ Й ДЛЯ НЕЙТРАЛЬНОГО ВІКНА ────────────────────
    # Стояла нижче, після хроми, — тобто ПІСЛЯ раннього `return True` нейтральної
    # гілки, і на нейтральному рядку була мертвим полем. Це трималось на думці,
    # що виключається завжди хроматичний колір (помада), якого нейтраль і так не
    # пропустить. Для приглушеної помади (#a9736b: C*24.1 при стелі нейтралі 24.0)
    # думка хибна: сусідні точки читаються як тепла нейтраль і проходили
    # нейтральним рядком того самого слота. Куля — це «цього КОЛЬОРУ тут не буває»,
    # і вікно, яким рядок дійшов до каталогу, до цього твердження не причетне.
    for куля in (запит.get("не_ближче_за") or ()):
        if de00(lab, куля["lab"]) < куля["ΔE00"]:
            return False
    if запит.get("нейтраль"):
        # ОДНЕ визначення нейтралі на всю систему — те саме, яким судить outfit.py
        if нейтраль(lab) is None: return False
        # ВИПРАВЛЕНО: тут стояв ранній return, і температурне вікно нейтралі (яке
        # palette.температура впорскувала в запит) НІХТО НЕ ЧИТАВ — напрям «нейтраль за
        # температурою особи» був інертний у точці контакту з каталогом. Тон для нейтралі
        # не годиться (при малій хромі h стрибає), тому вісь температури — b*.
        if запит.get("b_min") is not None and lab[2] < запит["b_min"]: return False
        if запит.get("b_max") is not None and lab[2] > запит["b_max"]: return False
        return True
    if not (запит["C_min"] <= C <= запит["C_max"]): return False
    # ── ВИКЛЮЧЕНА КУЛЯ: «не цей самий колір» ─────────────────────────────────
    # Вікно каже, ЯКИЙ колір годиться; це поле каже, який колір НЕ годиться, хоч і
    # лежить у вікні. Потрібне для анти-правила збігу з макіяжем (K-MUA-01): дірка
    # в центрі, а не звужене вікно, бо виключається КОЛІР (L, C, h разом), а не
    # смуга тону — сусідні відтінки того самого тону лишаються законними.
    # Сама перевірка перенесена вище (одразу за світлотою), щоб діяти й на
    # нейтральному вікні; тут лишився опис того, що вона означає.
    if запит.get("h_from") is None: return True
    a, b = запит["h_from"], запит["h_to"]
    return (a <= h <= b) if a <= b else (h >= a or h <= b)

# ── ЧАСТКА ВІКНА: колір-словом проти вікна людини — сила, не гейт ───────────
# ЗНАЙДЕНО ВИМІРОМ на 11 695 SKU Ager (measure_person_axis.py, 24.08.2026): коли
# колір речі відомий лише словом, гілка «назва_вікно» нижче віддавала ЦЕНТР вікна
# лексикону як точку, і `підходить` питала цю точку «так/ні». Наслідок: жодна
# хроматична річ не проходила жодного тонового вікна жодної людини (0 із 5650),
# а множини кандидатів для протилежних колоритів збігались (Жаккар 0.93–1.00).
# Вісь «які кольори кому» була інертна за побудовою — не через правила, а через
# те, що зону (вікно 40–60 L завширшки) питали як точку. Власний принцип корпусу —
# «людина — зона, не ярлик» — стосується й речі: слово кольору — зона.
# ЩО ЦЕ МІНЯЄ В РІШЕННІ: кандидатом стає річ, чиє вікно ХОЧ ЧАСТКОВО лежить у
# вікні людини, а її сила — ЧАСТКА вікна назви всередині вікна запиту. Частка
# різна для різних людей при тому самому слові — саме цього бракувало.
# ДЕ ЛАМАЄТЬСЯ: (1) частка припускає, що справжній колір речі рівномірно
# розподілений по вікну назви — це не виміряно; (2) вікна лексикону T3,
# некалібровані, тож частка успадковує їхню ширину; (3) це НЕ заміна виміру з фото:
# коли є lab із фото, працює старий шлях. Сила будь-якого числа звідси — hint.
_ЧАСТКА_КЕШ = {}
_ЧАСТКА_СІТКА = (4, 4, 6)     # вузлів по L, C, h; детерміновано, без Монте-Карло

def _ключ_запиту(q):
    return (q.get("L_min"), q.get("L_max"), q.get("C_min"), q.get("C_max"),
            q.get("h_from"), q.get("h_to"), bool(q.get("нейтраль")),
            q.get("b_min"), q.get("b_max"),
            tuple((tuple(k["lab"]), k["ΔE00"]) for k in (q.get("не_ближче_за") or ())))

def частка_вікна(вікно, q, сітка=_ЧАСТКА_СІТКА):
    """Частка вузлів сітки вікна назви (L×C×h), які проходять `підходить(вузол, q)`.
    0.0 — вікна не перетинаються; 1.0 — вікно назви цілком усередині вікна людини.
    Той самий `підходить`, що судить точки з фото, — щоб дві істини не розійшлись."""
    key = (tuple(вікно[:4]), tuple(вікно[4]) if вікно[4] else None, _ключ_запиту(q), сітка)
    if key in _ЧАСТКА_КЕШ: return _ЧАСТКА_КЕШ[key]
    Llo, Lhi, Clo, Chi, дуга = вікно
    nL, nC, nh = сітка
    Ls = [Llo + (Lhi-Llo)*(i+0.5)/nL for i in range(nL)]
    Cs = [Clo + (Chi-Clo)*(j+0.5)/nC for j in range(nC)]
    if дуга is None:
        hs = [360.0*k/nh for k in range(nh)]
    else:
        a, b = дуга; span = (b - a) % 360 or 360
        hs = [(a + span*(k+0.5)/nh) % 360 for k in range(nh)]
    ok = n = 0
    for L in Ls:
        for C in Cs:
            for h in hs:
                r = math.radians(h)
                n += 1
                if підходить((L, C*math.cos(r), C*math.sin(r)), q): ok += 1
    val = round(ok / n, 3) if n else 0.0
    _ЧАСТКА_КЕШ[key] = val
    return val

def описує_річ(lab, q, запас=10.0):
    """Чи рядок запиту взагалі КАЖЕ про цей колір — рід рядка проти роду речі.

    ПОТРІБНО ЛИШЕ ТАМ, ДЕ РІЧ УВІЙШЛА ЧАСТКОЮ (`частка_вікна`), а не точкою.
    Точку судить `підходить`, і на нейтральному рядку вона вимагає нейтралі
    (`нейтраль(lab) is None → False`). Для кольору-словом такої вимоги не було:
    частка > 0 означає «ХОЧ ОДИН вузол сітки вікна назви пройшов рядок», і
    пудровий топ (представник L*78 C*18 h*15) проходив рядком «нейтраль_запас»
    тим своїм краєм, де він блідий, — а в пул і в пакет їхав своїм представником,
    тобто рожевим. Рядок казав «нейтраль», річ казала «рожева», і обидва були в
    пулі як одне твердження.
    ЩО ЦЕ МІНЯЄ В РІШЕННІ (виміряно на стенді, гілка 0, схема «тональна»,
    каталог_повний): не-нейтралей у пулі 97, з них усередині вікон палітри й дуги
    схеми 4 (4.1 %). Рядками-нейтралями входило 86 із 97.
    ЧОМУ НЕ ВИМАГАЄМО `підходить` ВІД ПРЕДСТАВНИКА: саме це й було дефектом, який
    `частка_вікна` лікує (0 із 5650 хроматичних речей не проходили жодного тонового
    вікна, бо центр вікна лексикону широкий по L і C). Тут перевіряється НЕ вікно,
    а РІД: нейтральний рядок — нейтральну річ, рядок із дугою — тон у дузі. Світлота
    й хрома представника лишаються частці.
    ЗАПАС той самий 10°, що й у `pipeline._у_дузі_вікон` і `pipeline.схема_образу`:
    межа дуги — не лезо, і три місця системи не мають розходитись у тому, де вона.
    """
    try:
        L, C, h = lch(tuple(lab))
    except Exception:
        return True                     # кольору нема — рід не суперечить нічому
    if q.get("нейтраль"):
        return нейтраль(tuple(lab)) is not None
    if q.get("метал"):
        # рядок металу (K-PAL-11) — це теж РІД, а не просто дуга: без цього
        # золоте вікно (тон 70–100°) пускало яскраво-жовтий обруч (представник
        # C*62 при стелі золота 60) як «фурнітуру металу палітри».
        import palettes as _ПЛ
        return _ПЛ.метал_речі(tuple(lab)) == q["метал"]
    a, b = q.get("h_from"), q.get("h_to")
    if a is None or b is None:
        return True                     # тону не просили
    if нейтраль(tuple(lab)) is not None:
        return True                     # нейтраль законна під будь-яку дугу
    a, b = float(a) - запас, float(b) + запас
    return (a <= h <= b) if a <= b else (h >= a or h <= b)


def відстань_до_центру(lab, q):
    """Наскільки SKU близький до ЦЕНТРУ вікна, у ΔE00 до центральної точки.

    `відстань_до_вікна` міряє, наскільки річ ПОЗА вікном, і всередині вікна дає нуль
    для всіх — тобто для набору кандидатів, що ВСІ пройшли, вона не розрізняє нічого.
    Виправданий вибір (R-PSY-03) потребує осі, на якій кандидати вирівняні й різняться
    РІВНЕМ: центр вікна — це те, що ми насправді просили, а решта — компроміси.

    Міряється в ΔE00 (kL=1): річ↔точка-мішень, а не річ↔річ, тож текстильний kL=2
    з R-COL-11 тут НЕ застосовується — мішень не є тканиною."""
    L_ц = (q["L_min"] + q["L_max"]) / 2.0
    if q.get("нейтраль"):
        b_ц = ((q.get("b_min") if q.get("b_min") is not None else -2.0)
              + (q.get("b_max") if q.get("b_max") is not None else 2.0)) / 2.0
        мішень = (L_ц, 0.0, b_ц)
    else:
        C_ц = (q["C_min"] + q["C_max"]) / 2.0
        a, b = q.get("h_from"), q.get("h_to")
        if a is None:
            h_ц = lch(lab)[2]                    # тону не просили — він не штрафується
        else:
            дуга = (b - a) % 360 or 360
            h_ц = (a + дуга / 2.0) % 360
        мішень = (L_ц, C_ц*math.cos(math.radians(h_ц)), C_ц*math.sin(math.radians(h_ц)))
    return round(de00(tuple(lab), мішень), 2)

def відстань_до_вікна(lab, q):
    """Наскільки SKU не дотягує. Порожнє вікно саме по собі не рішення: одна річ
    «мимо на 3 одиниці світлоти» і «в каталозі нема нічого ближче 40» — це два
    різні висновки (розширити вікно проти відмовитись від схеми)."""
    L, C, h = lch(lab)
    dL = max(0, q["L_min"]-L, L-q["L_max"])
    if q.get("нейтраль"):
        # ВИПРАВЛЕНО НА РЕАЛЬНОМУ КАТАЛОЗІ: для нейтрального вікна відстань казала
        # «мимо на 0.0» про річ, яка вікну не відповідає — бо тест нейтралі
        # (коридори K-COL-06) у відстань не входив, а хрома для нього обнулялась.
        dC = 0.0 if нейтраль(lab) else max(2.0, C - 34.0 if C > 34 else 8.0)
        # відстань по температурі нейтралі — градуйована, щоб «мимо на 2 одиниці b*»
        # і «у каталозі лише теплі нейтралі» лишались різними висновками
        db = max(0.0, (q.get("b_min") or -1e9) - lab[2], lab[2] - (q.get("b_max") or 1e9))
        return dict(разом=round(dL + dC + db, 1), dL=round(dL, 1), dC=round(dC, 1),
                    db=round(db, 1), dh=0.0)
    else:
        dC = max(0, q["C_min"]-C, C-q["C_max"])
    dh = 0.0
    if q.get("h_from") is not None:
        a, b = q["h_from"], q["h_to"]
        усередині = (a <= h <= b) if a <= b else (h >= a or h <= b)
        if not усередині:
            dh = min(min(abs(h-a), 360-abs(h-a)), min(abs(h-b), 360-abs(h-b)))
    return dict(разом=round(dL + dC + dh*0.5, 1), dL=round(dL,1), dC=round(dC,1), dh=round(dh,1))

def хвилі(запити):
    """Рядки запиту, розділені на дві хвилі за полем `спроба`: (основні, запасні).

    ОДНЕ визначення черги на всю систему — щоб `покриття` і `composer` не розійшлись
    у тому, що таке «запасний рядок». Рядок без поля — основний: старі виклики й
    рукописні вікна в тестах не мусять нічого знати про черговість."""
    осн = [q for q in (запити or []) if not int((q or {}).get("спроба") or 0)]
    зап = [q for q in (запити or []) if int((q or {}).get("спроба") or 0)]
    return осн, зап


def покриття(запити, каталог, мін_впевненість=0.35, словник=None):
    """каталог: [dict(слот, lab, впевненість, group_id, назва, ціна)].
    Рахуються РІЗНІ моделі (group_id), а не SKU: одна модель у восьми кольорах —
    це один вибір, а не вісім (корпус: group_id критичний проти модального колапсу).

    R-PSY-03 (тема-8 §B.2, §B.5 — Chernev, Böckenholt & Goodman 2015, JCP 25(2)).
    ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after):
      before — `найкращий` рахувався ЛИШЕ в порожній гілці (як «наскільки не дотягує
               найближче»). Коли кандидатів багато, не позначалось нічого, а
               `приклади[:3]` різав список за порядком каталогу, тобто випадково.
      after  — рівно ОДИН кандидат позначений як виправданий вибір, у КОЖНІЙ гілці, і
               список НЕ вкорочується.
    Чому саме так, а не «показати менше»: у мета-аналізі 99 спостережень / 53 студій /
    N=7202 РОЗМІР НАБОРУ не є важелем — ні лінійно (b=−.005, t(37)=−1.5, p=.13), ні
    квадратично (b=.002, p=.17). Медіани «малого» (6) і «великого» (24) наборів
    ПЕРЕКРИВАЮТЬСЯ між експериментами: калібрувати нема чого. Найбільший
    задокументований переворот ЗНАКУ за СТАЛОГО розміру набору дає саме наявність
    домінантної / легко виправданої опції: d = −0.47, −0.46 з нею проти +0.45, +0.48
    без неї (Sela та ін. 2009, наб. 4 проти 12). Від'ємне d = більший набір КРАЩИЙ.

    ЧИМ ВИПРАВДАНИЙ ВИБІР ВИПРАВДАНИЙ. Потрібна причина, яку можна назвати одним
    реченням, і вона мусить лежати на осі, ПО ЯКІЙ КАНДИДАТИ ВИРІВНЯНІ (alignable —
    другий важіль із того самого списку). Усередині одного колірного вікна кандидати
    вирівняні за конструкцією: вони різняться РІВНЕМ однієї ознаки, а не наявністю
    різних. Тому виправдання — мінімальна відстань до центру вікна: «найточніше
    влучає в те, що ми шукали».

    ДЕ ЛАМАЄТЬСЯ. Жодного дослідження на ОДЯЗІ в мета-аналізі немає — там варення,
    шоколад, ручки, фотоапарати, фонди. Жодного з профілем людини в контурі.
    Відображення «профіль → articulated ideal point» — НАША гіпотеза, не вимір
    Chernev. Сила будь-якого твердження про перевантаження вибором як ГОЛОВНИЙ ефект
    не може перевищувати `hint` (§B.3: сторони сперечаються, і корпус ніс лише одну).
    Тут твердження вужче — про МАРКУВАННЯ, не про кількість, — і воно спирається на
    парні спостереження за сталого розміру набору, а не на головний ефект."""
    звіт = []
    def _сила(c, q):
        """Річ з фото — 1.0 якщо точка у вікні; річ зі словом — частка вікна назви."""
        if c.get("вікно"):
            return частка_вікна(c["вікно"], q)
        return 1.0 if підходить(c["lab"], q) else 0.0
    # ── ДВІ ХВИЛІ: ЗАПАСНИЙ РЯДОК НЕ РОЗМИВАЄ ПОВНИЙ СЛОТ (Н-palette-2-098) ──
    # Вікна слота йдуть диз'юнкцією, тож найширший рядок і вирішує, що таке
    # «підходить». Якірне нейтральне вікно (L 0–100 × C 0–24 × будь-який тон)
    # пропускало 97 % слота «взуття»/«сумка» — і колірний шар на цих слотах не
    # стверджував нічого. Прибрати рядок не можна: його завели проти ПОРОЖНЬОГО
    # слота, і порожній слот — гірша поломка.
    # Отже не звуження, а ЧЕРГА. Спершу рахуються рядки `спроба==0`; рядки
    # `спроба==1` беруться ЛИШЕ в тих слотах, де перша хвиля не дала ЖОДНОГО
    # кандидата. Слот далі не буває порожнім, але запасне вікно перестає
    # змагатися нарівні з основним.
    # ── КАТАЛОГ РОЗКЛАДАЄТЬСЯ ПО СЛОТАХ РАЗ, А НЕ СКАНУЄТЬСЯ НА КОЖЕН РЯДОК ──
    # (17.09.2026, швидкість.) Рядок вікна питає РІВНО один слот, а цикл нижче
    # тричі проходив увесь каталог заради нього: 193 рядки × 10 383 речі × 3 =
    # 6 млн порівнянь на руку, 3.9 с профільної шкали. Порядок усередині слота —
    # той самий, що в каталозі, тож `придатні` й `приклади` не рухаються ні на йоту.
    _по_слоту = {}
    for c in каталог:
        _по_слоту.setdefault(c["слот"], []).append(c)
    _сили_рядка = []
    for q in запити:
        сили = {}
        for c in _по_слоту.get(q["слот"]) or ():
            if c["впевненість"] < мін_впевненість: continue
            s = _сила(c, q)
            if s > 0.0: сили[id(c)] = s
        _сили_рядка.append(сили)
    _основне_дало = set()
    for q, сили in zip(запити, _сили_рядка):
        if сили and not int(q.get("спроба") or 0): _основне_дало.add(q["слот"])
    for q, сили in zip(запити, _сили_рядка):
        if int(q.get("спроба") or 0) and q["слот"] in _основне_дало:
            # «не бралась» ≠ «порожньо». Порожньо — це вимір: вікно питали, і в
            # ньому нікого нема. Тут вікна НЕ ПИТАЛИ, бо основна хвиля слота вже
            # дала кандидатів; `порожньо=None` тримає цю різницю видимою так само,
            # як гейти тримають «без входу» окремо від «впало».
            звіт.append(dict(слот=q["слот"], вікно=q, sku=0, моделей=0, приклади=[],
                             порожньо=None, спроба=1,
                             не_бралась="запасний рядок (спроба 1): основна хвиля "
                                        "слота «%s» дала кандидатів, тож запасне "
                                        "вікно не змагається з нею нарівні" % q["слот"]))
            continue
        придатні = [c for c in (_по_слоту.get(q["слот"]) or ()) if id(c) in сили]
        # словесні кандидати — за спаданням частки, точкові попереду (частка 1.0)
        придатні.sort(key=lambda c: -сили[id(c)])
        моделі = {c.get("group_id") or c["id"] for c in придатні}
        рядок = dict(слот=q["слот"], вікно=q, sku=len(придатні), моделей=len(моделі),
                     приклади=[c["назва"][:46] for c in придатні[:3]],
                     порожньо=len(придатні) == 0,
                     спроба=int(q.get("спроба") or 0))
        if not придатні:
            у_слоті = [c for c in (_по_слоту.get(q["слот"]) or ())
                       if c["впевненість"] >= мін_впевненість]
            if у_слоті:
                найкращий = min(у_слоті, key=lambda c: відстань_до_вікна(c["lab"], q)["разом"])
                d = відстань_до_вікна(найкращий["lab"], q)
                рядок["найближче"] = dict(назва=найкращий["назва"][:46], **d)
            else:
                рядок["найближче"] = dict(назва=None, разом=None,
                                          нота="у цьому слоті взагалі нема SKU з виміряним кольором")
        else:
            # ── R-PSY-03: рівно один позначений, список не вкорочено ──────────
            # серед найбільшої частки — найближчий до центру; для точкових (1.0) це старий критерій
            _макс = max(сили[id(c)] for c in придатні)
            _верх = [c for c in придатні if сили[id(c)] == _макс]
            найкращий = min(_верх, key=lambda c: відстань_до_центру(c["lab"], q))
            d = відстань_до_центру(найкращий["lab"], q)
            інші = [відстань_до_центру(c["lab"], q) for c in придатні
                    if c is not найкращий]
            відрив = (round(min(інші) - d, 2) if інші else None)
            # Слово для КОЛЬОРУ — не назва товару, а те, як цей колір зветься в
            # українському каталозі. Без нього шар пояснень не мав від коду
            # жодного кольорового слова й вигадував його сам.
            _підп = словник.підпис(найкращий["lab"]) if словник else None
            рядок["виправданий_вибір"] = dict(
                id=найкращий["id"], group_id=найкращий.get("group_id"),
                назва=найкращий["назва"][:46], ціна=найкращий.get("ціна"),
                колір_словом=(_підп or {}).get("назва"),
                колір_словом_чому=(_підп or {}).get("чому"),
                відстань_до_центру=d, відрив_від_другого=відрив,
                частка_вікна=(сили[id(найкращий)] if найкращий.get("вікно") else None),
                джерело_кольору=найкращий.get("джерело_кольору"),
                чому=("найточніше влучає у вікно: ΔE00 до центру %.2f проти %.2f у "
                      "наступного (відрив %.2f)" % (d, d + (відрив or 0), відрив)
                      if відрив is not None else
                      "єдиний кандидат у вікні — виправдання тривіальне"),
                # Виправдання мусить бути ЧЕСНИМ. Коли відрив менший за шум виміру
                # кольору з некаліброваного фото, «найточніший» — артефакт, а не факт.
                надійне=(відрив is None or відрив >= 1.0),
                застереження=(None if (відрив is None or відрив >= 1.0) else
                              "відрив %.2f менший за шум ΔE00 каталожного фото — "
                              "позначка тримається на різниці, тоншій за вимір; "
                              "показувати як «один із рівних», не як найкращий" % відрив))
            рядок["не_вкорочувати"] = (
                "усі %d SKU (%d моделей) лишаються в наборі. Кількість опцій не є "
                "важелем перевантаження (Chernev та ін. 2015: b=−.005, p=.13); важелі — "
                "маркування домінантної опції, вирівняність кандидатів і КІЛЬКІСТЬ "
                "ОЗНАК на опцію. `приклади` — це прев'ю для звіту, НЕ курація набору"
                % (len(придатні), len(моделі)))
        звіт.append(рядок)
    return звіт

# ═══════════════ 5. ЛЕКСИКОН НАЗВ КОЛЬОРІВ ═══════════════
class Словник:
    """ЗВОРОТНИЙ лексикон: колір → назва. Те, чого бракувало шару пояснень.

    ЩО ЦЕ ЛІКУЄ. `colorspace.describe(lab, lex=...)` додає полю `назва` людське
    слово — і кожен виклик у системі йшов із `lex=None`, бо каталогу
    `lexicons/*.json` не існує. Наслідок не косметичний: шар ШІ, який пише жінці
    пояснення, НЕ ОТРИМУВАВ ВІД КОДУ ЖОДНОГО СЛОВА ДЛЯ КОЛЬОРУ і мусив вигадувати
    його сам — при тому, що `language_gate` тримає дванадцять жорстких анти-правил
    саме на лексику, яка йде людині.

    ЧОМУ НЕ ФАЙЛ, А ФІД. Написати `lexicons/uk.json` руками означало б завести
    вигадані числа там, де в системі вже є ВИМІР: `лексикон()` збирає
    «назва → розподіл Lab» на реальних SKU і сама позначає назви, чий внутрішній
    розкид завеликий («ніжний», «мокко» — маркетинг, не колір). Цей клас лише
    обертає той самий вимір у зворотний бік. Жодного нового слова не вводиться:
    словник знає рівно ті назви, які реально стоять в українському каталозі.

    ⚠ ДЕ ЛАМАЄТЬСЯ: (1) словник не багатший за фід — на 4 назвах він і відповідає
    4 словами, і чесно мовчить на решті кольорового простору; (2) стеля 10.0 ΔE00
    успадкована від порога `придатна` в `лексикон()` — це та сама T3-константа, не
    друга; (3) назва — це те, як каталог НАЗИВАЄ колір, а не як його назвала б
    стилістка: «індиго» з фіду може бути тим, що людина зве «темно-синім»."""

    def __init__(self, лекс, стеля_de=10.0):
        self.назви = [(н, д) for н, д in (лекс or {}).items() if д.get("придатна")]
        self.відкинуто = [н for н, д in (лекс or {}).items() if not д.get("придатна")]
        self.стеля = float(стеля_de)

    def describe(self, L, rel, h):
        """Підпис під колір. `rel` — C/c_max, як його дає `colorspace.describe`."""
        if not self.назви or h is None:
            return None
        cm = c_max(L, h)
        C = (rel or 0.0) * cm
        lab = (L, C * math.cos(math.radians(h)), C * math.sin(math.radians(h)))
        н, d = min(((н, de00(lab, tuple(д["lab"]))) for н, д in self.назви),
                   key=lambda x: x[1])
        return н if d <= self.стеля else None

    def підпис(self, lab):
        """Те саме, але з діагностикою — для аудиту, не для тексту людині."""
        if not self.назви:
            return dict(назва=None, чому="лексикон порожній: у фіді нема назв, "
                                         "що пройшли поріг придатності")
        н, d = min(((н, de00(lab, tuple(д["lab"]))) for н, д in self.назви),
                   key=lambda x: x[1])
        return dict(назва=(н if d <= self.стеля else None), ΔE00=round(d, 1),
                    найближча=н, стеля=self.стеля, назв_у_словнику=len(self.назви),
                    чому=(None if d <= self.стеля else
                          "найближча назва «%s» на ΔE00 %.1f — далі за стелю %.1f; "
                          "код мовчить замість вигадати слово" % (н, d, self.стеля)))



def лексикон(каталог, мін_n=3, мін_впевненість=0.5):
    """Назва кольору з фіду -> виміряний розподіл Lab. Це Track D задарма:
    словник збирається на реальних SKU. Назви з великим внутрішнім розкидом
    позначаються — вони не колір, а маркетинг («ніжний», «стильний», «мокко»)."""
    # ── R-FEED-06: ОДИН ДИЗАЙН — ОДИН ГОЛОС ──────────────────────────────────
    # ЗНАЙДЕНО `аудит_фіду`, який на цьому й провалювався: докстрінг обіцяв словник
    # «на реальних SKU», і реалізація рахувала САМЕ SKU — тобто була ПОБАЙТОВО тим
    # самим, що й `_старий_лексикон`, з яким її порівнюють. Правку описали й не
    # зробили; стенд це показав, і його ніхто не запускав, бо він падав раніше.
    #
    # ЧОМУ ЦЕ НЕ КОСМЕТИКА: ходовий дизайн лежить у 6–7 розмірах, рештки — в одному.
    # Одне фото × 7 розмірів давало СІМ однакових вимірів Lab, медіанний розкид падав
    # до 0.0 — тобто гейт показував НАЙВИЩУ впевненість саме там, де доказ
    # найнадлишковіший, і ховав, що назва насправді покриває ΔE00 ≈ 17.
    #
    # Одиниця голосу — ДИЗАЙН: `фото_ключ` (те саме фото = та сама річ), інакше
    # `group_id`, інакше `id`. Фото попереду навмисно: воно й є те, з чого міряли
    # колір, тож два SKU з однаковим фото дають не два виміри, а один, повторений.
    голоси = {}
    for c in каталог:
        if not c.get("колір_назва") or c.get("впевненість", 0) < мін_впевненість:
            continue
        ключ = (c.get("фото_ключ") or c.get("group_id") or c.get("id"),
                c["колір_назва"].strip().lower())
        голоси.setdefault(ключ, []).append(c["lab"])
    гр, дублікатів = defaultdict(list), defaultdict(int)
    for (дизайн, назва), labs in голоси.items():
        # кілька SKU одного дизайну -> один вимір (медіана по них)
        гр[назва].append(tuple(statistics.median(x[i] for x in labs) for i in range(3)))
        дублікатів[назва] += len(labs) - 1
    out = {}
    for назва, labs in гр.items():
        if len(labs) < мін_n: continue
        центр = tuple(statistics.median(x[i] for x in labs) for i in range(3))
        розкид = statistics.median(de00(центр, l) for l in labs) if len(labs) > 1 else 0.0
        L, C, h = lch(центр)
        out[назва] = dict(n=len(labs), lab=[round(v, 1) for v in центр],
                          L=round(L, 1), C=round(C, 1), h=round(h, 1),
                          розкид=round(розкид, 1),
                          придатна=розкид < 10.0,
                          дизайнів=len(labs), згорнуто_sku=дублікатів[назва],
                          нота=None if розкид < 10 else
                               "розкид завеликий: назва не позначає колір однозначно")
    # R-FEED-06 [strong]: одиниця голосу — ДИЗАЙН, не SKU. Правило працює на кожному
    # виклику й доти не називало себе, тож лог не міг приписати йому жодну різницю.
    # У слід іде число, задля якого воно існує: скільки SKU згорнуто в дизайни.
    try:
        import trace as _СЛ
        _згорнуто = sum(дублікатів.values())
        _СЛ.запис("R-FEED-06", "лексикон рахує дизайни, не SKU", "фід",
                  значення="назв %d, згорнуто зайвих SKU %d" % (len(out), _згорнуто),
                  напрям=("дедуплікація спрацювала" if _згорнуто else
                          "дублів не було — кожен дизайн в одному SKU"))
    except Exception:
        pass
    return dict(sorted(out.items(), key=lambda kv: -kv[1]["n"]))


