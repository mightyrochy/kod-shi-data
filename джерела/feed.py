def прогін(шлях_фіду, специфікації, ліміт_фото=None, кеш="кеш_кольорів.json"):
    """специфікації: список виходів palette.запит_у_фід(...).
    Кеш кольорів на диску — щоб повторний прогін не качав фото заново.
    Каталог — із `_база_прогону`: див. коментар над нею, чому раз на процес."""
    _б = _база_прогону(шлях_фіду, ліміт_фото, кеш)
    # КОПІЯ ЗАПИСІВ, А НЕ САМІ ЗАПИСИ. Далі по конвеєру в запис ДОПИСУЮТЬ поля
    # (`каблук_є` у мості, `_частка_вікна` і `_доповнено` в композиторі), і рука C
    # не має діставати сліди руки B — доти кожна рука будувала свої записи з нуля.
    каталог = [dict(c) for c in _б["каталог"]]
    offers, розкиди, відкинуто, збої = _б["офферів"], _б["розкиди"], _б["відкинуто"], _б["збої"]
    звіти = [покриття(с, каталог) for с in специфікації]
    порожніх = sum(1 for z in звіти for q in z if q["порожньо"])
    усього = sum(len(z) for z in звіти)
    чисті = [r for r in розкиди if r]
    розкид_каталогу = round(statistics.median(чисті), 1) if чисті else None
    без_контролю = sum(1 for c in каталог if c.get("контроль") == "без контролю")
    return dict(
        відкинуто_контролем=len(відкинуто), приклади_відкинутих=відкинуто[:5],
        без_контролю=без_контролю,
        контроль_нота=("вимір, що суперечить назві товару або свотчу, у каталог НЕ йде "
                       "(verify.перевірити). «без контролю» = ні назви, ні свотча, "
                       "нічим перевірити — такі SKU лишаються, але позначені"),
        з_візерунком=sum(1 for c in каталог if c.get("візерунок") not in (None, "solid")),
        однотонних_зі_слова=sum(1 for c in каталог if c.get("візерунок") == "solid"),
        з_тканиною=sum(1 for c in каталог if c.get("текстура") or c.get("блиск") is not None),
        з_блиском_слово=sum(1 for c in каталог if (c.get("блиск") or 0) >= 1),
        з_сезоном=sum(1 for c in каталог if c.get("сезон_тканини")),
        з_рідом={р: sum(1 for c in каталог if c.get("рід_тканини_слово") == р)
                 for р in ("трикотаж", "полотно")},
        з_кроєм=sum(1 for c in каталог if c.get("крій")),
        з_описом_фото=sum(1 for c in каталог if c.get("збагачення")),
        колір_з_фото=sum(1 for c in каталог if c.get("колір_джерело") == "фото"),
        класи_мотиву={к: sum(1 for c in каталог if c.get("візерунок") == к)
                      for к in sorted({c.get("візерунок") for c in каталог
                                       if c.get("візерунок") not in (None, "solid")})},
        розкид_каталогу=розкид_каталогу,
        розкид_коментар=("медіанний розкид домінанти на фото цього магазину — "
                         "ЦЕ ВИМІР, а не константа: саме він задає, тонше чи грубше за "
                         "точність входу лежать пороги правил"),
        з_принтом=sum(1 for c in каталог if c.get("принт")),
        офферів=offers, у_слотах=_б["у_слотах"],
        без_слота=_б["без_слота"], з_кольором=len(каталог), збоїв_фото=збої,
        вікон=усього, порожніх_вікон=порожніх,
        частка_порожніх=round(порожніх/усього, 2) if усього else None,
        звіти=звіти, лексикон=лексикон(каталог),
        каталог=каталог,   # КОНТРАКТ: pipeline.підготувати читає це поле; його не було — кандидати гілок мовчали
        чесно="покриття рахується по SKU з кольором: фото-вимір АБО центр вікна назви (джерело_кольору, впевненість 0.35); "
              "непокриті категорії — у полі без_слота, їх не можна ігнорувати")
