    # Тобто правило сили `hard` виконувалось наполовину, і саме та половина, що
    # рятує читача від хибного висновку, була відсутня.
    #
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after):
    #   before — `run_outfit` друкує «офферів 41 → моделей 16, ключ розвʼязано 38%».
    #            Читач бере 16 як кількість моделей. На 38% розвʼязання це число —
    #            суміш моделей і фолбек-груп, і воно систематично ЗАВИЩЕНЕ:
    #            нерозвʼязані оффери розпадаються кожен у власну «модель».
