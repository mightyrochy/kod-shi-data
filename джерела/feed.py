def _число_см(v):
    """Число з param жниварки («4», «1.5», «22,5») або None. Порожнє й нечислове —
    None, а не 0: нуль тут означав би «каблука нема», і це вердикт, не мовчання."""
    if v in (None, ""):
        return None
    try:
        return float(str(v).strip().replace(",", "."))
    except (TypeError, ValueError):
        return None


def _взуттєві_поля(offer, тип=None):
    """Атрибути взуття: здогад із тексту, поверх нього — слово магазину.

    Один словник, не два сплати: `dict(**a, **b)` з тим самим ключем — TypeError,
    і на живому каталозі він валив увесь пул у нуль (спіймано прогоном 07.09.2026).
    """
    a = dict(взуттєві_атрибути(offer, тип))
    пар = offer.get("параметри") or {}
    явні = dict(матеріал_верху=((пар.get("матеріал_верху") or "").strip().lower() or None),
                каблук_см=_число_см(пар.get("каблук_см")),
                халява_см=_число_см(пар.get("халява_см")))
    for k, v in явні.items():
        if v is not None:
            a[k] = v
            if k == "каблук_см":
                a["каблук"] = v > 0
    return a


def взуттєві_атрибути(offer, тип=None):
    """Атрибути взуття з категорії й назви. None означає «не названо», НЕ «нема»:
    різниця вирішальна, бо на None правило виходить питанням, а на False — вердиктом."""
    тип = тип or тип_речі(offer)
    текст = f"{offer.get('категорія','')} {offer.get('назва','')} {offer.get('опис','') or ''}".lower()
    a = dict(виріз_стопи=ВИРІЗ_ЗА_ТИПОМ.get(тип),
             халява_рівень=ХАЛЯВА_ЗА_ТИПОМ.get(тип, None),
             халява_джерело=("виведено з типу «%s»" % тип) if тип in ХАЛЯВА_ЗА_ТИПОМ else None)
    # каблук: спершу число з назви, далі — категорія «на підборах / без підборів»
    м = _ПРО_КАБЛУК.search(текст)
    if м:
        a["каблук_см"] = float(м.group(1).replace(",", ".")); a["каблук"] = True
    elif any(x in текст for x in _БЕЗ_КАБЛУКА):
        a["каблук"] = False; a["каблук_см"] = 0.0
    elif any(x in текст for x in _З_КАБЛУКОМ):
        a["каблук"] = True            # висоти нема → accessory видасть питання
    # устілка: таблиця розмірів ГЛУШИТЬ одиничне читання (число в ній належить
    # конкретному розміру, а обраного розміру пари жоден шар не тримає), одиничне
    # число пишеться лише в межах фізично можливої довжини — див. коментар до
    # `_ПРО_УСТІЛКА_ПАРА`.
    if not _ПРО_УСТІЛКА_ПАРА.search(текст):
        м = _ПРО_УСТІЛКА.search(текст)
        if м:
            _у = float(м.group(1).replace(",", "."))
            if ДІАПАЗОН_УСТІЛКИ_СМ[0] <= _у <= ДІАПАЗОН_УСТІЛКИ_СМ[1]:
                a["устілка_см"] = _у
    for м_ in МАТЕРІАЛИ_ВЕРХУ:
        if м_ in текст:
            a["матеріал_верху"] = м_; break
    for п in ПІДОШВИ:
        if п in текст:
            a["підошва"] = п; break
    # ── ТРИ СТАНИ, А НЕ ДВА (17.09.2026, K-PRC-02) ──────────────────────────
    # Доти поле ставилось ЛИШЕ в True: «прошит» → True, решта → ключа нема. Тобто
    # клеєна пара була невідрізненна від пари, що про конструкцію мовчить, і
    # правило про другий множник ціни не мало нижнього боку взагалі — воно вміло
    # лише хвалити. Тепер станів три, як і всюди у файлі: True (прошита), False
    # (клеєна, перевзути не можна), ключа нема (картка не називає).
    # ВИМІРЯНО на `каталог_повний.xml` (2 096 пар взуття): «прошит» 4 картки,
    # «клеєн» 2. Разом 6 із 2 096 — 0.3 %. Число мале й чесне: український роздріб
    # конструкцію низу називає рідко, і саме це, а не наша обережність, є межею
    # K-PRC-02. Ставити «клеєна» дефолтом для решти 2 090 означало б вигадати
    # твердження продавця, якого він не робив.
    if "прошит" in текст:
        a["ремонтопридатна"] = True
    elif "клеєн" in текст or "клеен" in текст:
        a["ремонтопридатна"] = False
    # повнота й розмірність — див. коментар над `_ПРО_ПОВНОТУ`
    _чистий = _ШАБЛОН_РОЗМІРНОСТІ.sub(" ", текст)
    м = _ПРО_ПОВНОТУ.search(_чистий)
    if м:
        a["повнота"] = _ПОВНОТА_СЛОВО.get(м.group(1) or м.group(2))
    # розмірність рахує `розмірність_речі`: той самий розбір тепер читає ВСЯ
    # система, а не лише взуттєва гілка (K-SIZ-02)
    a["розмірність"] = розмірність_речі(offer)
    return {k: v for k, v in a.items() if v is not None}


