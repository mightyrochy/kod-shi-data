КАТАЛОГИ_НА_ДИСКУ = ("каталог_повний.xml", "каталог_жіночий.xml",
                     "каталог_чоловічий.xml", "каталог_стенд.xml")


def каталог_на_диску(перевага=None, тека=None):
    """Шлях до першого каталогу, який СПРАВДІ лежить поруч АБО НА РІВЕНЬ ВИЩЕ.
    Кидає SystemExit із адресою розпакування, коли нема жодного: мовчазний
    фолбек на неіснуючий файл уже коштував трьох приладів.

    ЧОМУ ДВА МІСЦЯ, А НЕ ОДНЕ (10.09.2026, наряд Н-V34-064). У git архів лежить
    у КОРЕНІ репозиторію (`каталог_повний.xml.gz`), а прилади живуть у
    `джерела/`. Пошук лише «поруч» означав, що на чистій викачці, де
    розпакованого файла ще нема, `аудит_слотів` і `траса_петлі` падали
    SystemExit-ом ДО першого виміру — rc=1 і порожній stdout, який читається як
    «нема розбіжностей». Шукаються тільки чотири ТОЧНІ імені з
    `КАТАЛОГИ_НА_ДИСКУ`, тож підхопити чужий файл вище нема чим.

    ЦІЛЬ ЗАПИСУ — ЗАВЖДИ `тека`, хоч би де знайшовся архів: розпаковувати 44 МБ
    у корінь репозиторію означало б лікувати себе, засмічуючи чуже дерево."""
    тека = тека or os.path.dirname(os.path.abspath(__file__)) or "."
    for ім in ([перевага] if перевага else []) + list(КАТАЛОГИ_НА_ДИСКУ):
        if os.path.isabs(ім):
            місця, ціль = [ім], ім
        else:
            ціль = os.path.join(тека, ім)
            місця = [ціль, os.path.join(тека, "..", ім)]
        # ГОТОВИЙ .xml ПЕРШИМ В ОБОХ МІСЦЯХ, і лише потім .gz в обох: інакше
        # архів поруч переважив би вже розпакований файл вище й перезаписав те,
        # що хтось поклав руками.
        for ш in місця:
            if os.path.exists(ш):
                return ш
        # .gz — КОНВЕНЦІЯ РЕПОЗИТОРІЮ, а не виняток: великі каталоги лежать
        # стиснутими (`.gitignore` тримає розпакований поза git). Одним місцем
        # на всі каталоги й на обидві теки: розпакованого нема — беремо архів,
        # хоч би де він лежав, і кладемо ПОРУЧ ІЗ ПРИЛАДОМ.
        for ш in місця:
            if os.path.exists(ш + ".gz"):
                import gzip as _gz, shutil as _sh
                with _gz.open(ш + ".gz", "rb") as _вх, open(ціль, "wb") as _вих:
                    _sh.copyfileobj(_вх, _вих)
                return ціль
    raise SystemExit(
        "жодного каталогу нема на диску (шукав: %s).\n"
        "Дивився і поруч, і на рівень вище:\n"
        "  %s\n  %s\n"
        "У репозиторії каталог лежить стиснутим, і .gz розпаковується сам —\n"
        "значить, нема й архіву: візьміть його з репозиторію."
        % (", ".join(КАТАЛОГИ_НА_ДИСКУ), os.path.abspath(тека),
           os.path.abspath(os.path.join(тека, ".."))))


# ── КАТАЛОГ ЧИТАЄТЬСЯ РАЗ НА ПРОЦЕС, А НЕ РАЗ НА РУКУ (17.09.2026, швидкість) ──
# `запити` кличе `прогін` ДВІЧІ — рукою B (людина) і рукою C (донор), — і обидва
# рази з тим самим фідом, тим самим `ліміт_фото` і тим самим кешем кольорів.
# Виміряно на каталог_повний (10 770 оферів): 45 МБ XML розбирались двічі (8.6 с
# профільної шкали лише на `_parse_whole`), і весь цикл виміру кольору, контролю
# `verify` й атрибутів проганявся двічі — 35.8 с із 56.4.
# ЩО ЗАЛЕЖИТЬ ВІД СПЕЦИФІКАЦІЙ, А ЩО НІ. Від них залежать РІВНО `звіти`
# (`покриття`) і лічба вікон; сам каталог, лексикон і всі лічильники — ні. Тому
# тут кешується база, а `звіти` рахуються щоразу заново: інакше кеш мовчки віддав
# би руці C покриття вікон руки B, тобто збрехав би саме в тому числі, заради
# якого прогін і робиться двічі.
# КЛЮЧ НЕСЕ mtime І РОЗМІР ФАЙЛА: перечитаний або переписаний фід не має права
# прийти з кеша. Слот один — база важить як каталог, і тримати дві нема за що.
_КЕШ_БАЗИ = {}


def _база_прогону(шлях_фіду, ліміт_фото=None, кеш="кеш_кольорів.json"):
    """База прогону (каталог + лічильники) з кешем за ВСІМА її входами."""
    # ЗБАГАЧЕННЯ — ТРЕТІЙ ВХІД, І ВІН НЕ ФАЙЛ. `читати_збагачення` саме́ кешоване за
    # (шлях, mtime), тож виклик тут дармовий, — але порівнювати його ФАЙЛОМ мало:
    # `проби/zbah_фід.py` міряє внесок опису з фото, ПІДМІНЯЮЧИ саму функцію
    # (`F.читати_збагачення = lambda: {}`), і файл при цьому не рухається. Ключ за
    # файлом віддав би другому прогону каталог ПЕРШОГО — проба показала це відразу:
    # «колір з фото 0.0 %» там, де його 92 %. Тому в ключі стоїть САМ словник, за
    # тотожністю, і кеш тримає на нього посилання: незмінений файл віддає той самий
    # об'єкт (влучання), підміна функції — новий (промах, тобто чесний перерахунок).
    зб = читати_збагачення()
    try:
        _ст = os.stat(шлях_фіду)
        # КЕШ КОЛЬОРІВ — ТЕЖ ВХІД, І ВІН РУХАЄТЬСЯ МІЖ ПРОГОНАМИ. При `ліміт_фото` > 0
        # прогін міряє чергову порцію фото й дописує її у файл кеша — отже ДРУГИЙ
        # прогін у тому самому процесі законно дає ІНШИЙ каталог (на порцію більше
        # виміряних кольорів). Без цього поля в ключі база віддала б перший каталог
        # назавжди, і прогресивне наповнення кеша тихо спинилось би на першій порції.
        # На продуктовому шляху `ліміт_фото` завжди 0 (`bridge._входи_пакета`), нічого
        # не міряється, файл не переписується (див. `_змінено` нижче) — і рука C
        # дістає базу з кеша, заради чого він і стоїть.
        _стк = os.stat(кеш) if кеш and os.path.exists(кеш) else None
        ключ = (os.path.abspath(шлях_фіду), ліміт_фото, кеш, _ст.st_mtime_ns, _ст.st_size,
                (_стк.st_mtime_ns, _стк.st_size) if _стк else None)
    except OSError:
        ключ = None
    _є = _КЕШ_БАЗИ.get(ключ) if ключ is not None else None
    if _є is not None and _є[0] is зб:
        return _є[1]
    б = _прочитати_каталог(шлях_фіду, ліміт_фото, кеш, зб)
    if ключ is not None:
        _КЕШ_БАЗИ.clear()
        _КЕШ_БАЗИ[ключ] = (зб, б)
    return б


# R-FEED-08 — дубль `feed._прочитати_каталог`: без param кольору слово назви входить\n# вікном лексикону з упевненістю 0.35.
