def читати_збагачення(тека=None):
    """{id: опис} з `каталог_збагачення.json` (або `.json.gz`) поруч із feed.py.
    Порожній словник, коли файла нема. Кешується за (шлях, mtime): прогін
    кличуть на кожен запит, а файл — мегабайти."""
    тека = тека or os.path.dirname(os.path.abspath(__file__)) or "."
    for ш in (os.path.join(тека, ЗБАГАЧЕННЯ_ІМ), os.path.join(тека, ЗБАГАЧЕННЯ_ІМ + ".gz")):
        if not os.path.exists(ш):
            continue
        ключ = (ш, os.path.getmtime(ш))
        if ключ not in _ЗБАГАЧЕННЯ_КЕШ:
            import gzip as _gz
            with (_gz.open(ш, "rt", encoding="utf-8") if ш.endswith(".gz")
                  else open(ш, encoding="utf-8")) as f:
                _ЗБАГАЧЕННЯ_КЕШ.clear()
                _ЗБАГАЧЕННЯ_КЕШ[ключ] = json.load(f)
        return _ЗБАГАЧЕННЯ_КЕШ[ключ]
    return {}


