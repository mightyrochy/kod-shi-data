# ── СЕПАРАТОРИ КОЛЬОРУ ЗА ДІАЛЕКТАМИ (D7) ──────────────────────────────────
# Rozetka пише «Олива, Хакі» (кома), Prom — «Олива | Білий» (пайп), Google-подібні —
# «Black/Green» (слеш, за спаданням помітності). Один сепаратор на всі три діалекти
# зливав би багатоколірну річ в одну назву, і `лексикон` учився б на сміттєвій мітці.
_СЕП_КОЛЬОРУ = re.compile(r"\s*[,|/]\s*|\s+та\s+|\s+і\s+")

def _текст_параметра(p):
    """D6 + D8: <value lang="uk"> має пріоритет; <br/> НЕ обриває значення.

    D6: Rozetka дає двомовний param двома <value lang="…">. `p.text` у такому вузлі
    порожній, тож стара версія віддавала None — тобто КОЛІР ГУБИВСЯ ЦІЛКОМ на
    найпоширенішому діалекті.
    D8: `<param>Олива<br/>Друге</param>` — `p.text` дає лише «Олива», бо решта лежить
    у `tail` дитини. Стара версія обрізала параметр на першому теґі."""
    знач = p.findall("value")
    if знач:
        uk = [v for v in знач if (v.get("lang") or "").lower().startswith("uk")]
        обр = (uk or знач)[0]
        return _склеїти(обр)
    return _склеїти(p)

_БЛОКОВІ = ("br", "p", "li", "div")

def _склеїти(вузол):
    """Текст вузла з дітьми. ЗНАЙДЕНО НА ПРОБІ ЦІЄЇ Ж ПРАВКИ: наївний `itertext()`
    давав «ОливаДруге значення» — два РІЗНІ значення, злиплі в одне слово, бо <br/>
    сам тексту не має. Далі це йде в `лексикон` як окрема кольороназва, і на живому
    фіді така назва трапиться рівно один раз, тобто засмітить словник синглтоном.
    Блокові теґи мусять давати РОЗДІЛЬНИК, а не порожнечу."""
    части = []
    if вузол.text: части.append(вузол.text)
    for д in вузол:
        if (д.tag or "").lower() in _БЛОКОВІ: части.append(", ")
        части.append("".join(д.itertext()))
        if д.tail: части.append(д.tail)
    return " ".join("".join(части).split()).strip(" ,")

def _ключ_моделі(o, params):
    """D1 + D2: ЯК розв'язано модель, і ЧЕСНО — якою гілкою.

    Rozetka НЕ має group_id у специфікації взагалі (тема-7): там один оффер на
    РОЗМІР, а модель розв'язується через `article`/`vendorCode`. Prom кладе group_id
    АТРИБУТОМ, експорт Prom→Rozetka — ДИТИНОЮ. Без цих трьох гілок «моделей» у звіті
    покриття виходить стільки ж, скільки SKU, і `feed.покриття` рахує вісім кольорів
    однієї сукні як вісім різних виборів."""
    g = o.get("group_id")
    if g: return g.strip(), "group_id-атрибут (Prom)"
    д = o.findtext("group_id")
    if д and д.strip(): return д.strip(), "group_id-дитина (Prom→Rozetka експорт)"
    for поле, мітка in (("article", "article"), ("vendorCode", "vendorCode"),
                        ("model", "model")):
        v = o.findtext(поле)
        if v and v.strip():
            return v.strip(), "%s (Rozetka: group_id у специфікації відсутній)" % мітка
    # ── R-FEED-01, ТРЕТЯ ГІЛКА ЛАНЦЮГА (тема-7 §2): vendor + categoryId + стем назви ──
    # Корпус називає її прямо; в коді її не було — після article ішов фолбек на id.
    # ФЕЙЛ-КЕЙС (24.08.2026, ager_brief.xml): кожен РОЗМІР — окремий оффер без
    # group_id/article, id має форму <модель>_<варіант>, назва однакова для всіх
    # розмірів. Виміряно: 260 офферів = 124 дизайни (назва ↔ url ↔ префікс id
    # збігаються 124/124/124). Фолбек на id давав розв'язання 0 %, і композитор
    # брав «5 кандидатів» = 4 розміри однієї футболки + 1 — де-факто K_НА_СЛОТ=2, а
    # пул колірно однорідний: K-COL-01 блокував КОЖНУ з 25 комбінацій (тепла-світла),
    # бо іншого кольору в пулі не було. Тут розміри одного дизайну стають однією
    # моделлю. Де ламається: магазин пише в назві розмір або окремий стем на розмір
    # (стем нижче зрізає лише явні «розмір/размер/size …» і хвостові S–XXL) — тоді
    # ключ роздроблюється, як і було; дві РІЗНІ моделі з побайтово однаковою назвою
    # злипнуться (у межах одного vendor+categoryId — на 124 назвах ager таких 0).
    назва, _ = _назва(o)
    if назва:
        return ("%s|%s|%s" % ((o.findtext("vendor") or "").strip().lower(),
                              (o.findtext("categoryId") or "").strip(), _стем_назви(назва)),
                "vendor+categoryId+стем назви (R-FEED-01 гілка 3: group_id/article відсутні)")
    return o.get("id"), "ФОЛБЕК на id оффера — модель НЕ розв'язана, SKU = модель"


_РОЗМІР_У_НАЗВІ = re.compile(
    r"[,;(]?\s*(розмір|размер|size)\s*[:\-]?\s*[\w/\-–]+\)?\s*$|"
    r"[,;\s]+(xxs|xs|s|m|l|xl|xxl|xxxl|\d{2}(?:-\d{2})?)\s*$", re.I)

def _стем_назви(назва):
    """Стем назви для ключа моделі: без явного розміру на хвості, у нижньому регістрі,
    з нормалізованими пробілами. Кольору НЕ зрізає: колір — інша модель для магазину."""
    s = " ".join(назва.split()).lower()
    попередній = None
    while s != попередній:
        попередній = s
        s = _РОЗМІР_У_НАЗВІ.sub("", s).strip(" ,;")
    return s

def _назва(o):
    """D9: `name_ua` має пріоритет над `name`; `type="vendor.model"` збирає назву з
    typePrefix+vendor+model і <name> ІГНОРУЄТЬСЯ (так велить специфікація YML)."""
    if (o.get("type") or "").strip() == "vendor.model":
        части = [o.findtext("typePrefix"), o.findtext("vendor"), o.findtext("model")]
        зібрано = " ".join(x.strip() for x in части if x and x.strip())
        if зібрано: return зібрано, "type='vendor.model' (складено; <name> ігноровано)"
    for поле, мітка in (("name_ua", "name_ua"), ("name", "name"),
                        # `<model>` як остання підстава: у частині фідів назви нема
                        # зовсім, а модель є. Краще неповна назва, ніж порожня —
                        # від назви залежить `тип_речі`, а від нього весь шар
                        # формальності.
                        ("model", "model (назви нема, узято модель)")):
        v = o.findtext(поле)
        if v and v.strip(): return v.strip(), мітка
    return "", "НАЗВИ НЕМА — тип речі не виведеться, шар формальності замовкне"

def _доступність(o):
    """D4 + D5: `available=""` у Prom означає НЕМА (не «невідомо» й не «є»);
    `stock_quantity=0` ПЕРЕМАГАЄ `available="true"`.

    Стара версія рахувала `o.get("available") != "false"` — тобто порожній рядок
    ставав True, і речі, яких нема на складі, йшли в рекомендацію. Це найдорожчий
    із десяти дефектів: система пропонує купити те, чого не купиш."""
    сток = o.findtext("stock_quantity")
    if сток is not None and сток.strip().isdigit() and int(сток.strip()) == 0:
        return False, "stock_quantity=0 (перемагає available)"
    a = o.get("available")
    if a is None: return None, "атрибута available нема — невідомо"
    a = a.strip().lower()
    if a == "": return False, 'available="" (Prom: порожнє = НЕМА)'
    if a in ("true", "1"): return True, "available=true"
    if a in ("false", "0"): return False, "available=false"
    return None, "available=%r — нерозпізнане" % a

