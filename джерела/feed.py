def тип_набору(offer):
    """Тип цілого комплекту за словами частин: «костюм» (діловий, 7–9),
    «костюм_повсякденний» (3–5) або «комплект» (без підказки — широкий інтервал)."""
    т = _re_тип.sub(" ", f"{offer.get('назва','')}".lower())
    if _ДІЛОВИЙ.search(т) and not _ПОВСЯКДЕННИЙ.search(т):
        return "костюм"
    if _ПОВСЯКДЕННИЙ.search(т):
        return "костюм_повсякденний"
    return "комплект"


def набір_цілий(offer):
    """True — SKU є цілим образом (верх+низ). None — не набір. False — набір, але
    не цілий (дві речі одного слота), і він лишається у своєму слоті."""
    т = f"{offer.get('назва','')}".lower()
    т = _re_тип.sub(" ", т)                    # «костюмний» — прикметник
    if not _НАБІР.search(т):
        return None
    if __import__("re").search(r"\bкостюм\b", т):
        return True                            # голий іменник: суть слова — дві речі
    return bool(_ВЕРХ_СЛОВО.search(т) and _НИЗ_СЛОВО.search(т))


def тип_речі(offer, слот=None):
    """Тип речі з категорії й назви. None — коли жоден ключ не збігся.

    `слот="сумка"` перевіряє сумочні типи ПЕРШИМИ. Спіймано гейтом: «Клатч
    вечірній» діставав тип «вечірня_сукня», бо ключ «вечірн» стоїть на початку
    словника, — і клатч судився як сукня з формальністю 9. Порядок словника не
    може бути правильним для всіх слотів одразу; слот — той контекст, якого
    словнику бракувало.

    None НЕ підмінюється дефолтом навмисно: тип керує формальністю, і вигаданий тип
    дав би образу формальність, якої ніхто не міряв. Скільки SKU лишились без типу —
    видно в `прогін().без_типу`, і це число і є роздільна здатність цього шару."""
    текст = f"{offer.get('категорія','')} {offer.get('назва','')}".lower()
    # «КОСТЮМНИЙ ЖАКЕТ» — НЕ КОСТЮМ (04.09.2026, вимір: 56 речей). Ключ «костюм»
    # ловив прикметник, і жакет із костюмної тканини діставав тип «костюм» з
    # формальністю 8 — шар формальності судив жакет як діловий костюм. Прикметник
    # знімається з тексту, іменник лишається (те саме розрізнення, що в
    # аудит_слотів._прикметник).
    текст = _re_тип.sub(" ", текст)
    if слот == "сумка":
        for т, ключі in ТИП_КЛЮЧІ:
            if т in ТИПИ_СУМОК and any(k in текст for k in ключі): return т
    for т, ключі in ТИП_КЛЮЧІ:
        if any(k in текст for k in ключі): return т
    # сукня без уточнення — тип є, але формальність її НЕ визначена одним словом
    if "сукн" in текст or "плать" in текст: return "сукня_без_уточнення"
    # ── ОГОЛОШЕНИЙ ТИП ЖНИВАРКИ — ЛИШЕ ЯК ЗАПАСНИЙ (27.08.2026) ────────────────
    # Назва — точніша за розділ магазину («LeBERDES Мокасини» лежить у розділі
    # «лофери»: 51 SKU), тому слово назви йде першим. Запасний потрібен там, де
    # назви фактично нема: «Перлинний молоко» (костюм), «Бордо шоколад» (спідниця) —
    # 143 SKU каталогу жниварки мали тип у param і None тут, а без типу мовчить
    # увесь шар формальності. Приймається лише слово з власного словника типів.
    _оголош = ((offer.get("параметри") or {}).get("тип") or "").strip().lower()
    # «костюм» від жниварки приймається лише коли в назві є ІМЕННИК костюм:
    # «Берет з костюмної тканини» мав param тип=костюм (4 речі) — і формальність 8.
    # (перша версія відкидала «костюм» і при ПОРОЖНІЙ назві — а «Перлинний молоко»
    # + param тип=костюм законно бере оголошений тип; гейт §? це спіймав.)
    if _оголош == "костюм" and _re_тип.search(f"{offer.get('назва','')}".lower()):
        _оголош = ""
    if _оголош in ІМЕНА_ТИПІВ: return _оголош
    return None


ІМЕНА_ТИПІВ = frozenset([т for т, _ in ТИП_КЛЮЧІ] + ["сукня_без_уточнення", "костюм_повсякденний", "комплект"])

def розкласти_по_слотах(offers):
    """Непокриті категорії ПОВЕРТАЮТЬСЯ, а не мовчки зникають: якщо половина фіду
    не лягла в слоти, число покриття буде красиве й брехливе."""
    по_слотах, без_слота = defaultdict(list), defaultdict(int)
    for o in offers:
        s = слот(o)
        (по_слотах[s].append(o) if s else без_слота.__setitem__(
            o["категорія"] or "(без категорії)", без_слота[o["категорія"] or "(без категорії)"]+1))
    return dict(по_слотах), dict(без_слота)

