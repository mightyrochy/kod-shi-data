def _фото_придатне(ф):
    """Виміряно на каталог_повний 04.09.2026: 867 речей несли «фото», яке не є фото —
    629 свотчів 50×50 (25union), 127 порожніх data:svg (feelyou, morandi), 49 GIF 1×1
    lazy-load (bella-bicchi), 59 data:png 1×1 (rito, intimo). Вони йшли моделі в опис
    («ФОТО НЕ ТЕ», вердикти 1 і 4) і в примірку (400 «Unable to process input image»,
    вердикт 8). GIF Gemini не приймає взагалі. Мініатюра ≤ 120 px — свотч, не фото."""
    if not ф or ф.strip().lower().startswith("data:"):
        return False
    if re.search(r"\.gif(?:$|\?)", ф, re.I):
        return False
    м = _МІНІАТЮРА.search(ф)
    if м and max(int(м.group(1)), int(м.group(2))) <= 120:
        return False
    return True


def _фото_нормоване(ф):
    """`//host/…` без схеми: браузер домальовує, воркер (Cloudflare) — ні."""
    return ("https:" + ф) if ф.startswith("//") else ф


def чисті_фото(фото, url=""):
    """Лише ті картинки, що можуть бути фото САМЕ ЦІЄЇ речі."""
    вих = [_фото_нормоване(ф) for ф in (фото or [])
           if ф and not _НЕ_ФОТО.search(ф) and _фото_придатне(ф)]
    м = re.search(r"-(\d{3,})/?$", url or "")
    if м and вих:
        ном = "/%s/" % м.group(1)
        свої = [ф for ф in вих if ном in ф]
        # ЛИШЕ КОЛИ Є ДОКАЗ: якщо хоч одна картинка несе номер товару з url, то
        # картинки з ІНШИМ номером у шляху — чужий товар (gepur). Коли номера нема
        # в жодній (vsisvoi: у шляху дата й інший id) — доказу нема, нічого не
        # чіпаємо; перша версія цього правила зняла 201 із 202 фото vsisvoi.
        if свої:
            вих = свої + [ф for ф in вих if not re.search(r"/\d{3,}/", ф)]
        # GEPUR — ВИНЯТОК ІЗ «НЕМА ДОКАЗУ»: їхній CDN завжди кладе id товару в шлях
        # (`/products/NNNNN/<id>/…`), тож коли ЖОДНА картинка не несе id з url —
        # усі вони чужі (сережки 49962 і кольє 49958 мали одне фото товару 49929;
        # спіймано карткою 22:40). Без фото — чесно; з чужим — брехня.
