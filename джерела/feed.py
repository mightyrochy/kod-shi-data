def каталог_на_диску(перевага=None, тека=None):
    """Шлях до першого каталогу, який СПРАВДІ лежить поруч. Кидає SystemExit із
    адресою розпакування, коли нема жодного: мовчазний фолбек на неіснуючий файл
    уже коштував трьох приладів."""
    тека = тека or os.path.dirname(os.path.abspath(__file__)) or "."
    for ім in ([перевага] if перевага else []) + list(КАТАЛОГИ_НА_ДИСКУ):
        ш = ім if os.path.isabs(ім) else os.path.join(тека, ім)
        if os.path.exists(ш):
            return ш
        # .gz — КОНВЕНЦІЯ РЕПОЗИТОРІЮ, а не виняток: великі каталоги лежать
        # стиснутими (`.gitignore` тримає розпакований поза git), і стенд уже
        # розпаковує `каталог_повний.xml.gz` сам. Тут те саме, одним місцем на
        # всі каталоги: розпакованого нема — беремо архів і кладемо поруч.
        if os.path.exists(ш + ".gz"):
            import gzip as _gz, shutil as _sh
            with _gz.open(ш + ".gz", "rb") as _вх, open(ш, "wb") as _вих:
                _sh.copyfileobj(_вх, _вих)
            return ш
    raise SystemExit(
        "жодного каталогу нема на диску (шукав: %s).\n"
        "У репозиторії він лежить стиснутим — розпакуйте:\n"
        "  gunzip -c ../каталог_повний.xml.gz > %s/каталог_повний.xml"
        % (", ".join(КАТАЛОГИ_НА_ДИСКУ), тека))


