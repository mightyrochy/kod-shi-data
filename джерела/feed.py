def читати_yml(шлях):
    """YML (Yandex Market) — формат Rozetka / Prom / Horoshop.

    Повертає (offers, діагностика). ДІАГНОСТИКА ОБОВ'ЯЗКОВА, не додаток: покриття
    ключа моделі й розподіл гілок — це і є роздільна здатність усього шару даних.
    Якщо ключ розв'язано для 40% офферів, будь-яке число «моделей» нижче за течією
    брехливе, і це має бути видно ДО того, як хтось на нього спреться.

    ЩО ЦЕ МІНЯЄ (before/after): стара версія читала лише `<name>`, `group_id`-атрибут
    і `p.text`. На фікстурі трьох діалектів, побудованій за специфікаціями
    (Rozetka p185/p188/p205, Prom 360004963538, Google Merchant), вона провалювала
    ВСІ ДЕСЯТЬ названих дефектів: губила колір на двомовному param, читала товар без
    залишку як наявний, рахувала три розміри однієї сукні як три моделі."""
    root = ET.parse(шлях).getroot()
    кат = {c.get("id"): dict(назва=(c.text or "").strip(), батько=c.get("parentId"))
           for c in root.iter("category")}
    def шлях_кат(cid):
        імена, seen = [], set()
        while cid and cid in кат and cid not in seen:
            seen.add(cid); імена.append(кат[cid]["назва"]); cid = кат[cid]["батько"]
        return " / ".join(reversed(імена))
    offers = []
    гілки_ключа, гілки_назви, гілки_дост = defaultdict(int), defaultdict(int), defaultdict(int)
    for o in root.iter("offer"):
        params = {(p.get("name") or "").strip().lower(): _текст_параметра(p)
                  for p in o.findall("param")}
        ключ, гілка_к = _ключ_моделі(o, params)
        назва, гілка_н = _назва(o)
        дост, гілка_д = _доступність(o)
        гілки_ключа[гілка_к] += 1; гілки_назви[гілка_н] += 1; гілки_дост[гілка_д] += 1
        сирий = params.get("колір") or params.get("цвет") or params.get("color")
        части = [x for x in _СЕП_КОЛЬОРУ.split(сирий) if x] if сирий else []
        # ── ID І КЛЮЧ МОДЕЛІ — УНІКАЛЬНІ В МЕЖАХ КАТАЛОГУ, НЕ МАГАЗИНУ (28.08.2026) ──
