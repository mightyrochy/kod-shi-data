_БРАКУЄ = {"кольори": "colours", "зріст": "height", "нагода": "occasion_or_her_words"}
_АКСЕСУАРНІ = {"довжина_стопи_мм": "foot_length_mm", "обхват_голови_см": "head_girth_cm"}


def _число(v):
    """Число виміру або None: порожнє, нуль і не число — не вимір."""
    try:
        ч = float(v)
    except (TypeError, ValueError):
        return None
    return (int(ч) if ч.is_integer() else round(ч, 1)) if ч > 0 else None


def _обхват(к):
    return _ВМ.код("girth", к) or к


def _колір(слово):
    с = str(слово or "").split("·")[0].strip()
    return (_ВМ.код("color_name", с) or с) if с else None


def стан(с):
    """Факти показу (`станДляШі`) → стан для моделі: англійські ключі, коди внутрішньої мови,
    числа. Чого показ не дав — того в стані нема (а не «невідомо»: це її екран, не знання)."""
    с = с if isinstance(с, dict) else {}
    п, сц, пал = с.get("профіль") or {}, с.get("сценарій") or {}, с.get("палітра") or {}
    вих = {"screen": _ЕКРАН.get(с.get("екран"), с.get("екран"))}
    if с.get("крок"):
        вих["onboarding_step"] = int(с["крок"])
    обх = {_обхват(к): _число(v) for к, v in (п.get("обхвати") or {}).items() if _число(v)}
    профіль = {"name": п.get("назва") or None, "profiles_on_phone": п.get("профілів"),
               "created": п.get("створено"), "colours_read": п.get("кольори"),
               "height_cm": _число(п.get("зріст")), "girths_cm": обх or None,
               "face_answers_of_4": п.get("що_до_лиця"),
               "portrait_photo": (п.get("фото") or {}).get("портрет"),
               "full_length_photo": (п.get("фото") or {}).get("зріст")}
    профіль.update({_АКСЕСУАРНІ[к]: _число(v) for к, v in (п.get("аксесуарні") or {}).items()
                    if к in _АКСЕСУАРНІ and _число(v)})
    вих["profile"] = {к: v for к, v in профіль.items() if v is not None}
    поля = dict(сц.get("поля") or {})
    типові = [_Д._ПОЛЯ_ВИПАДКУ.get(к, к) for к in (поля.pop("типові_поля", None) or [])]
    випадок = {"name": сц.get("назва") or None, "saved": сц.get("збережений"),
               "unsaved_changes": сц.get("змінено"), "passport": сц.get("паспорт") or None,
               "confirmed": сц.get("підтверджено"), "fields": _Д.випадок(поля) or None,
               "form_defaults": типові or None,
               "refused_zones": [_Д.код("zone", з) for з in сц.get("зони") or []] or None}
    вих["case"] = {к: v for к, v in випадок.items() if v is not None}
    палітра = {"base": _колір(пал.get("основа")),
               "scheme": _Д._СХЕМА.get(пал.get("схема"), пал.get("схема")) or None,
               "gamut": _ГАМА.get(пал.get("гама"), пал.get("гама")) or None}
    вих["palette"] = {к: v for к, v in палітра.items() if v is not None}
    вих["missing_to_build"] = [_БРАКУЄ.get(к) or _обхват(к) for к in с.get("бракує") or []]
    for ключ, де in (("образів", "outfits_on_screen"), ("збережених", "saved_cases")):
        if isinstance(с.get(ключ), int):
            вих[де] = с[ключ]
    return вих


def промпт(питання, довідка, стан_показу, розмова=None, мова_тексту=None):
    """Промпт моделі: її питання, розмова досі, довідка про застосунок і стан (див. шапку)."""
    репліки = [{"from": "her" if р.get("хто") == "людина" else "you", "text": str(р.get("текст") or "")}
               for р in розмова or [] if isinstance(р, dict) and str(р.get("текст") or "").strip()]
    дані = dict(question=str(питання or "").strip(), conversation=репліки,
                app=str(довідка or "").strip(), state=стан(стан_показу))
    return _json.dumps(_ЗП.зібрати(ДОВІДКА, дані, мова_тексту=мова_тексту), ensure_ascii=False)


def помічниця(вхід):
    """Ендпойнт моста `помічниця`: {питання, довідка, стан, розмова?, мова_тексту?} → {промпт}."""
    d = _json.loads(вхід) if isinstance(вхід, str) else (вхід or {})
    for к in ("питання", "довідка"):
        if not str(d.get(к) or "").strip():
            return _json.dumps(dict(помилка="нема поля «%s»" % к), ensure_ascii=False)
    return _json.dumps(dict(промпт=промпт(d["питання"], d["довідка"], d.get("стан") or {},
                                          d.get("розмова"), d.get("мова_тексту"))),
                       ensure_ascii=False)
