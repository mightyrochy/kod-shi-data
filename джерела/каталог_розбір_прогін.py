def вибірка(офери, на_групу=НА_ГРУПУ, сід=СІД):
    """[(група, офер)] — по `на_групу` з кожної групи, сідом `сід`. Річ, що підійшла до кількох
    груп, лишається в ПЕРШІЙ: вибірка не має мірити ту саму річ двічі."""
    слоти, взяті, вих = {}, set(), []
    for o in офери:
        try:
            слоти[o["id"]] = ФС.слот(o)
        except Exception:                             # noqa: BLE001 — падіння слота теж вибірка
            слоти[o["id"]] = None
    for ім, _, підходить in ГРУПИ:
        пул = [o for o in офери if o["id"] not in взяті and підходить(o, слоти[o["id"]])]
        пул.sort(key=lambda o: o["id"])               # сід без порядку нічого не важить
        обрані = random.Random("%s-%s" % (сід, ім)).sample(пул, min(на_групу, len(пул)))
        взяті.update(o["id"] for o in обрані)
        вих.extend((ім, o) for o in обрані)
    # Перший прогін ще не має кодів типу. Добираємо решту до заданого обсягу
    # незалежно від класифікації, інакше перехід читачів на коди замикає розбір на собі.
    бракує = min(len(офери), на_групу * len(ГРУПИ)) - len(вих)
    if бракує > 0:
        решта = sorted((o for o in офери if o["id"] not in взяті), key=lambda o: o["id"])
        вих.extend(("без_розбору", o) for o in random.Random("%s-решта" % сід).sample(решта, бракує))
    return вих


class Годинник:
    """ГОДИННИК ПРОГОНУ (наряд 4.4, Р21): кожна спроба виклику моделі — запис із будь-якого потоку.

    Навіщо один на обидва прогони розбору. Вибір навантаження ноутбука (рядки 6429, 6546: А — річ на
    виклик, цей файл; Б — рядок полів на виклик, `прилади/розбір_рядків_5192.py`) доти порівнював дві
    різні лічби: А — «с/річ стіною» лише в друку, Б — медіану секунд виклику × рядки / parallel. Медіана
    не бачить хвоста й простою пулу між пачками, тож Б і А виміряні не одним годинником. Тут — один:
    стінний час кожної стадії (від першого старту до останньої відповіді, паралельність уже в ньому) на
    зроблену одиницю, помножений на всі одиниці каталогу (`прогноз`)."""

    def __init__(self, паралельно=1):
        """Порожній журнал спроб; `паралельно` — лише мітка в зведенні (у стінному часі вона вже є)."""
        self.записи, self.паралельно, self._лок = [], паралельно, threading.Lock()

    def записати(self, запис):
        """Дописує спробу (стадія, т0, т1, токени, обрив, причина повтору) — потокобезпечно."""
        with self._лок:
            self.записи.append(запис)

    def зведення(self):
        """Логічні виклики, спроби (зокрема впалі й заглушки), повтори та час за стадіями й разом."""
        def нове():
            return dict(викликів=0, спроб=0, впало=0, заглушок=0, обривів=0, повторів={},
                        модель_с=0.0, вхід_т=0, вихід_т=0, _т0=None, _т1=None)
        дія, стадії = нове(), {}
        with self._лок:
            записи = list(self.записи)
        for з in записи:
            for ц in (дія, стадії.setdefault(з["стадія"], нове())):
                ц["спроб"] += 1
                ц["викликів"] += 0 if з.get("спроба") or з.get("причина") else 1
                ц["впало"] += bool(з.get("помилка"))
                ц["заглушок"] += bool(з.get("заглушка"))
                ц["обривів"] += 1 if з.get("обрив") else 0
                if з.get("причина"):
                    ц["повторів"][з["причина"]] = ц["повторів"].get(з["причина"], 0) + 1
                ц["модель_с"] += з["т1"] - з["т0"]
                ц["вхід_т"] += з.get("вхід_т") or 0
                ц["вихід_т"] += з.get("вихід_т") or 0
                ц["_т0"] = з["т0"] if ц["_т0"] is None else min(ц["_т0"], з["т0"])
                ц["_т1"] = з["т1"] if ц["_т1"] is None else max(ц["_т1"], з["т1"])
        for ц in [дія] + list(стадії.values()):
            ц["стінний_с"] = round((ц.pop("_т1") or 0) - (ц.pop("_т0") or 0), 1)
            ц["модель_с"] = round(ц["модель_с"], 1)
        return dict(паралельно=self.паралельно, дія=дія, стадії=стадії)

    def прогноз(self, одиниці):
        """Години на весь обсяг тим самим темпом стіною: `одиниці` — {стадія: (зроблено, всього)}.
        Стадія без успішних одиниць або із заглушкою темпу моделі не має."""
        з, вих = self.зведення()["стадії"], {}
        for ст, (зроблено, всього) in одиниці.items():
            if зроблено and ст in з and not з[ст]["заглушок"]:
                вих[ст] = dict(зроблено=зроблено, всього=всього, с_на_одиницю=round(з[ст]["стінний_с"] / зроблено, 2),
                               годин=round(з[ст]["стінний_с"] / зроблено * всього / 3600, 1))
        return dict(стадії=вих, годин=round(sum(в["годин"] for в in вих.values()), 1))


def _обрив(е):
    """Чи виняток — обрив з'єднання (сервер не відповів), а не відповідь сервера з кодом HTTP."""
    if isinstance(е, urllib.error.HTTPError):
        return False
    return isinstance(е, (ConnectionError, socket.timeout, TimeoutError, urllib.error.URLError))


def надіслати(тіло, годинник=None, стадія="річ", повтор=None):
    """(текст відповіді, секунд) — від сервера моделі форми OpenAI (`АДРЕСА`, MODEL_URL); кожна спроба — у
    `годинник`. Швидкий обрив з'єднання — один повтор із причиною `connection_reset` (`ОБРИВ_ШВИДКИЙ_С`);
    решта винятків — вгору, як доти. Одна дорога для прогонів А і Б (`прилади/розбір_рядків_5192.py`)."""
    дані = json.dumps(тіло, ensure_ascii=False).encode("utf-8")
    початок = time.time()
    for спроба in range(2):
        запис = dict(стадія=стадія, спроба=спроба, т0=time.time(),
                     причина="connection_reset" if спроба else повтор)
        try:
            запит = urllib.request.Request(АДРЕСА + "/chat/completions", data=дані,
                                           headers={"Content-Type": "application/json"})
            with urllib.request.urlopen(запит, timeout=3600) as в:
                відп = json.loads(в.read().decode("utf-8"))
        except Exception as е:                        # noqa: BLE001 — спробу названо в годиннику, виняток іде вгору
            if isinstance(е, urllib.error.HTTPError):
                тіло_помилки = е.read().decode("utf-8", errors="replace")
                запис.update(http_status=е.code, http_body=тіло_помилки)
                е = RuntimeError("HTTP %d: %s" % (е.code, тіло_помилки or е.reason))
            запис.update(т1=time.time(), обрив=_обрив(е), помилка="%s: %s" % (type(е).__name__, е))
            повторити = запис["обрив"] and not спроба and запис["т1"] - запис["т0"] <= ОБРИВ_ШВИДКИЙ_С
            if годинник:
                годинник.записати(запис)
            if not повторити:
                raise е
            time.sleep(2 + 2 * random.random())
            continue
        вжито = відп.get("usage") or {}
        запис.update(т1=time.time(), вхід_т=вжито.get("prompt_tokens") or 0, вихід_т=вжито.get("completion_tokens") or 0)
        if годинник:
            годинник.записати(запис)
        вибір = (відп.get("choices") or [{}])[0]
        return ((вибір.get("message") or {}).get("content") or ""), round(запис["т1"] - початок, 1)


def модель(промпт, ід_моделі, сід=None, схема=True, годинник=None, повтор=None, стадія="річ",
           макс_токенів=None, ім_схеми=ІМ_СХЕМИ):
    """(текст відповіді, секунд) від локальної моделі форми OpenAI; виняток — вгору, його пише
    прогін у файл речі, а не ковтає. `схема` — граматика відповіді (`response_format` зі
    `КР.схема_відповіді`); `сід` — для повтору: той самий промпт, інша вибірка токенів;
    `годинник` — спроби в годинник прогону (`надіслати`); `повтор` — причина повторного виклику.
    Сам заданий сід повтору не означає. Короткий виклик сусідів (`каталог_розбір_сусіди`): `схема` —
    словник JSON Schema, `ім_схеми`, `макс_токенів` і `стадія` годинника — свої."""
    тіло = dict(model=ід_моделі, messages=[dict(role="user", content=промпт)], stream=False,
                max_tokens=макс_токенів or int(os.environ.get("MODEL_MAX_TOKENS") or МАКС_ТОКЕНІВ))
    if схема:
        тіло["response_format"] = {"type": "json_schema", "json_schema": {
            "name": ім_схеми, "strict": True, "schema": схема if isinstance(схема, dict) else КР.схема_відповіді()}}
    if os.environ.get("MODEL_TEMP"):
        тіло["temperature"] = float(os.environ["MODEL_TEMP"])
    if сід is not None:
        тіло["seed"] = сід
    return надіслати(тіло, годинник, стадія, повтор=повтор)


def _спитати(повід, ід_моделі, схема=True, годинник=None, стадія="річ", макс_токенів=None, ім_схеми=ІМ_СХЕМИ,
             придатна=None):
    """(відповідь, секунд усього, впало, повторів) — з `ПОВТОРІВ_НА_НЕ_JSON` повторами (іншим
    сідом), поки відповідь не розбирається як JSON. Беремо ПЕРШУ, що розібралась; коли жодна —
    першу, щоб у файлі лишилось те, що модель сказала. Впалий виклик (мережа, сервер) повтором
    не лікується — його названо окремо. `придатна(текст)` — що вважати розібраною відповіддю
    (типово — повний розбір `КР.з_відповіді`)."""
    придатна = придатна or (lambda т: КР.з_відповіді(т)[0] is not None)
    перша, секунд, спроба = None, 0.0, 0
    початок = time.time()
    for спроба in range(1 + ПОВТОРІВ_НА_НЕ_JSON):
        try:
            текст, с = модель(повід, ід_моделі, спроба or None, схема, годинник,
                              повтор="invalid_json" if спроба else None, стадія=стадія,
                              макс_токенів=макс_токенів, ім_схеми=ім_схеми)
        except Exception as е:                        # noqa: BLE001 — впалий виклик названий
            return перша or "", round(time.time() - початок, 1), "%s: %s" % (type(е).__name__, е), спроба
        секунд += с
        перша = текст if перша is None else перша
        if придатна(текст):
            return текст, round(секунд, 1), None, спроба
    return перша or "", round(секунд, 1), "invalid_json: відповіді не розібрано", спроба


def _схема_речі(o, мова, схема):
    """Граматика на річ (5.4-Г «цитата»): цитата коду типу — дослівний відрізок назви цієї речі.
    Без граматики (`схема` ложне) — як доти."""
    if not схема:
        return схема
    назва = (КР.частини_тексту(КР.вхід(o, мова)).get("name") or [None])[0]
    return КР.схема_відповіді(назва)


def ід_еталону(шлях):
    """id речей з файла еталону: JSON-список (рядків чи обʼєктів з «id»), JSON-обʼєкт (ключі-id
    або список під «речі»/«items»), чи текст — id першим словом рядка. Форму еталону РЗ-Е пише
    паралельна сесія, тож читається будь-яка з цих — порядком файла."""
    with open(шлях, encoding="utf-8") as ф:
        сире = ф.read()
    try:
        дані = json.loads(сире)
    except ValueError:
        return [р.split()[0] for р in сире.splitlines() if р.strip() and not р.startswith("#")]
    if isinstance(дані, dict):
        дані = next((дані[к] for к in ("речі", "items", "еталон") if isinstance(дані.get(к), list)),
                    [к for к in дані if "@" in к])
    return [д["id"] if isinstance(д, dict) else str(д) for д in дані
            if not isinstance(д, dict) or д.get("id")]


def група_речі(o, слот):
    """Перша група `ГРУПИ`, що бере річ, або «решта» — як у `вибірка`."""
    return next((ім for ім, _, підходить in ГРУПИ if підходить(o, слот)), "решта")


def _готова(шлях, повід, схема=True):
    """Відповідь із файла попереднього запуску — коли ЗАПИТ у ньому той самий знак у знак (та сама
    річ, те саме правило) і відповідь не порожня; інакше None, і річ іде в модель. Інше правило —
    інший запит, тож відповіді двох правил в одній теці так не змішаються. З граматикою (`схема`)
    відповідь ще й та, яку пускає НИНІШНЯ схема (`КР.за_схемою`, 5.4-Г): схема в запит не входить,
    тож без цього звуження граматики брало б відповіді ширшої без перевірки."""
    if not os.path.exists(шлях):
        return None
    with open(шлях, encoding="utf-8") as ф:
        запит, _, відп = ф.read().partition("\n\n── ВІДПОВІДЬ\n")
    відп = відп[:-1] if відп.endswith("\n") else відп
    вузол = схема if isinstance(схема, dict) else None
    return (відп if запит == "── ЗАПИТ\n" + повід and відп.strip() and (not схема or КР.за_схемою(відп, вузол))
            else None)


def _записати(куди, мірка):
    """`прогін.json` — через тимчасовий файл і заміну: обірваний запис не псує попередній."""
    шлях = os.path.join(куди, "прогін.json")
    with open(шлях + ".tmp", "w", encoding="utf-8") as ф:
        json.dump(мірка, ф, ensure_ascii=False, indent=1)
    os.replace(шлях + ".tmp", шлях)


def прогін(ід_моделі, мова=КР.МОВА, куди=None, на_групу=НА_ГРУПУ, сід=СІД, усі=False, ті_самі=None,
           паралельно=ПАРАЛЕЛЬНО, еталон=None, нових=0, схема=True, сусіди=None):
    """Вибірку — через модель у теку. Один файл на річ («── ЗАПИТ», «── ВІДПОВІДЬ»), плюс
    `прогін.json` з міркою кожного виклику. Повертає шлях теки.

    `усі` — ПОВНИЙ КАТАЛОГ: кожна група цілком, а речі, яких жодна група не взяла, — групою
    «решта» (на `каталог_повний.xml` 27.09 — 3 з 11 993: слот коду поза групами). Річ, що вже має
    відповідь у теці під тим самим запитом (`_готова`) і в мірці попереднього запуску, у модель
    вдруге не йде — так перерваний прогін докатується тією самою командою.

    `ті_самі` — тека попереднього прогону: ті самі речі в тих самих групах і тому самому порядку.
    ЧОМУ НЕ СІД. Вибірка тим самим сідом на main 27.09 — уже НЕ ті 300 речей, що прогнав ноутбук
    на f02325e: спільних id 158 з 300 (між цими комітами змінилось читання каталогу —
    `фід_каталог`, `фід_розбір`, — а з ним пули груп). «До/після» правила на різних речах
    міряло б різницю вибірок, а не правила.

    `еталон` (РЗ-К, пілот) — файл id еталону очима (`ід_еталону`): ці речі першими, а за ними
    `нових` речей, яких в еталоні нема, — `вибірка` сідом `сід` по ⌈нових/10⌉ на групу. Еталон
    міряє правдивість кодів, нові — що правило не підігнане під еталон.
    `паралельно` — скільки запитів водночас (`ПАРАЛЕЛЬНО`); `схема` — граматика відповіді.

    `сусіди` (наряд 5.4-С; менеджер 25.10, п.4а) — `None` (кожна річ повним розбором, як доти) чи режим
    кольору сусідів, «значення» або «річ» (`каталог_розбір_сусіди`): річ, що має сусіда в групі прогону
    (рівні всі слова, крім кольору й розміру), повним розбором не йде — її файл пишеться з відповіді
    представника, колір — коротким викликом. Імена файлів і нумерація ті самі; рядок мірки такої речі має
    `сусід_від` (id представника). Сусід, чий представник упав або чий колір виклик не дав, іде повним
    розбором у цьому ж запуску."""
    офери, _ = ФР.читати_yml(ФК.каталог_на_диску(), показ=False)
    за_ід = {o["id"]: o for o in офери}
    if еталон:
        ід = [і for і in ід_еталону(еталон) if і in за_ід]
        слоти = {}
        for і in ід:
            try:
                слоти[і] = ФС.слот(за_ід[і])
            except Exception:                         # noqa: BLE001 — падіння слота теж вибірка
                слоти[і] = None
        пари = [("еталон_" + група_речі(за_ід[і], слоти[і]), за_ід[і]) for і in ід]
        решта = [o for o in офери if o["id"] not in set(ід)]
        пари += вибірка(решта, -(-нових // len(ГРУПИ)), сід)[:нових] if нових else []
        print("еталон %s: %d речей у каталозі · нових %d" % (еталон, len(ід), len(пари) - len(ід)))
    elif ті_самі:
        with open(os.path.join(ті_самі, "прогін.json"), encoding="utf-8") as ф:
            взірець = json.load(ф)["речі"]
        пари = [(р["група"], за_ід[р["id"]]) for р in взірець if р["id"] in за_ід]
        print("ті самі речі, що в %s: %d з %d (решти в каталозі на диску нема)"
              % (ті_самі, len(пари), len(взірець)))
    else:
        пари = вибірка(офери, len(офери) if усі else на_групу, сід)
    if усі and not ті_самі and not еталон:
        взяті = {o["id"] for _, o in пари}
        пари += [("решта", o) for o in офери if o["id"] not in взяті]
    куди = куди or os.path.join(ТУТ, "..", "аудит", "розбір_каталогу",
                                "%s_%s" % (ід_моделі.replace("/", "_"), мова))
    os.makedirs(куди, exist_ok=True)
    було = {}
    if os.path.exists(os.path.join(куди, "прогін.json")):
        with open(os.path.join(куди, "прогін.json"), encoding="utf-8") as ф:
            було = {р["id"]: р for р in json.load(ф).get("речі", []) if not р.get("впало")}
    мірка = dict(модель=ід_моделі, мова=мова, url=АДРЕСА, сід=сід, паралельно=паралельно,
                 граматика=bool(схема), макс_токенів=int(os.environ.get("MODEL_MAX_TOKENS")
                                                           or МАКС_ТОКЕНІВ),
                 на_групу=("еталон %s + нових %d" % (os.path.basename(еталон), нових) if еталон
                           else "як у %s" % os.path.basename(os.path.normpath(ті_самі)) if ті_самі
                           else "усі" if усі else на_групу),
                 задача=КР.РОЗБІР[мова].задача, речі=[])
    готові, чекають, речі_файли = {}, [], {}
    for і, (група, o) in enumerate(пари, 1):
        # Компактний JSON (РЗ-К): відступи — це ~700 пробілів і переносів на запит, які модель
        # читає як токени, а не зміст (вимір у коміті).
        повід = json.dumps(КР.промпт(o, мова), ensure_ascii=False)
        ім = "%02d_%s_%s.txt" % (і, група, o["id"].replace("/", "_").replace("@", "_"))
        речі_файли[і] = (ім, повід)
        # Готова відповідь впізнається за id речі й запитом, не за іменем файла: ім'я несе індекс і
        # групу, а вони змінюються, щойно з'являються коди (`вибірка` читає `ФС.слот`, `КД.код`).
        рядок = було.get(o["id"])
        if рядок and _готова(os.path.join(куди, рядок["файл"]), повід, схема) is not None:
            готові[і] = рядок
        else:
            чекають.append((і, група, o, ім, повід))
    if усі and not ті_самі and not еталон:
        # Частинами по ~12 год (наряд 5.4-Н, п.4б): речі в наявності йдуть у модель першими. Лише ПОРЯДОК
        # обробки — індекс `і` в імені файла й сам запит не змінюються, тож докат упізнає вже розібране.
        чекають.sort(key=lambda р: р[2].get("available") is not True)

    def _одна(робота):
        """Одна річ у моделі: файл на диск, рядок мірки назад. Іде в потоці, тож спільного не пише
        нічого — ні `мірка`, ні друку; ім'я файла їй уже дане, тож два потоки не беруться за один."""
        і, група, o, ім, повід = робота
        відп, секунд, впало, повторів = _спитати(повід, ід_моделі, _схема_речі(o, мова, схема), годинник)
        with open(os.path.join(куди, ім), "w", encoding="utf-8") as ф:
            ф.write("── ЗАПИТ\n%s\n\n── ВІДПОВІДЬ\n%s\n" % (повід, відп))
        return і, dict(файл=ім, id=o["id"], група=група, секунд=секунд, знаків_запиту=len(повід),
                       знаків_відповіді=len(відп), впало=впало, повторів=повторів)

    т0, годинник = time.time(), Годинник(паралельно)
    сусідні, відкладені = {}, []
    if сусіди:
        повні = {і for і, р in готові.items() if not р.get("сусід_від")}
        сусідні = {п + 1: д + 1 for п, д in С.розподіл(пари, lambda п: п + 1 in готові,
                                                       lambda п: п + 1 in повні).items()}
        відкладені = [р for р in чекають if р[0] in сусідні]
        чекають = [р for р in чекають if р[0] not in сусідні]
        мірка["сусіди"] = dict(колір=сусіди)
        вже = {п: д for п, д in сусідні.items() if д in готові}      # представник давно розібраний — сусіди одразу
        запасні = _сусіди_фаза(пари, готові, вже, відкладені, речі_файли, куди, ід_моделі, сусіди, паралельно,
                               годинник, мірка) if вже else []
        сусідні = {п: д for п, д in сусідні.items() if п not in вже}
        чекають = [р for р in чекають if р[0] not in сусідні]
        відкладені = [р for р in відкладені if р[0] in сусідні]
        чекають += запасні

    def _виконати(список):
        """Повний розбір речей `список` пачками по `ЗАПИС_КОЖНІ` з записом мірки після кожної."""
        for край in range(0, len(список), ЗАПИС_КОЖНІ):
            пачка = список[край:край + ЗАПИС_КОЖНІ]
            if паралельно > 1:
                with concurrent.futures.ThreadPoolExecutor(max_workers=паралельно) as пул:
                    вийшло = list(пул.map(_одна, пачка))
            else:
                вийшло = [_одна(р) for р in пачка]
            for (і, рядок), робота in zip(вийшло, пачка):
                готові[і] = рядок
                print("%2d/%d %-18s %-28s %5.1f с%s %s"
                      % (і, len(пари), робота[1], робота[2]["id"][:28], рядок["секунд"],
                         " ×%d" % (рядок["повторів"] + 1) if рядок["повторів"] else "   ",
                         рядок["впало"] or ""))
            мірка["речі"] = [готові[і] for і in sorted(готові)]
            _записати(куди, мірка)

    _виконати(чекають)
    if сусідні:
        запасні = _сусіди_фаза(пари, готові, сусідні, відкладені, речі_файли, куди, ід_моделі, сусіди, паралельно,
                               годинник, мірка)
        _виконати(запасні)
        чекають = чекають + запасні
    мірка["речі"] = [готові[і] for і in sorted(готові)]
    мірка["годинник"] = годинник.зведення()
    _записати(куди, мірка)
    впали = sum(1 for р in мірка["речі"] if р["впало"])
    нові = [готові[і] for і, *_ in чекають]
    успішно = sum(1 for р in нові if not р["впало"])
    повторено = sum(р.get("повторів", 0) for р in нові)
    хід = time.time() - т0
    сусідів = sum(1 for р in мірка["речі"] if р.get("сусід_від"))
    print("тека: %s · речей %d · готових з попереднього запуску %d (з них сусідів %d) · впало викликів %d · повторів "
          "на не-JSON %d · паралельно %d · %s с/успішну річ стіною (%d успішних із %d нових за %.1f хв) · лічба: "
          "проби/каталог_розбір_лічба.py"
          % (куди, len(пари), len(пари) - len(чекають), сусідів, впали, повторено, паралельно,
             "%.1f" % (хід / успішно) if успішно else "нема", успішно, len(чекають), хід / 60))
    _годинник_у_теку(куди, годинник, {"річ": (успішно, len(офери))})
    зібрати(куди)
    return куди


