# ── ЧИСТОТА РЯДКА `features`: ОДИН КРИТЕРІЙ НА ПРОБУ І НА ПОВТОР (РЗ-1) ─────
# ЧОМУ ТУТ, А НЕ В ПРОДУКТІ. Критерій ЧИТАЄ СЛОВА англійського рядка, а п.12 забороняє це коду
# продукту. Цей модуль у продукт не входить (жоден модуль показу чи пулу його не імпортує —
# лише проби й ноутбук), тож слова живуть тут, в одному місці: проба
# `проби/каталог_розбір_заборони.py` і крок `--підставити` беруть їх звідси, а не мають кожен
# свій. Інакше «чисто» для проби й «чисто» для повтору розійшлись би — і повтор підставляв би
# рядки, які проба далі рахує брудними.
# Правило §3 «Ноутбук» (`аудит/ПЕРЕДАЧА.md`) словами менеджера: МОЖНА нюанси кольору, посадки,
# тканини, крою і склад тканини; НЕ МОЖНА назву кольору, що дублює код (крім кольорів візерунка),
# розмір і обміри, маркетинг і оцінки, бренд і назву моделі, країну, відгук покупця, догляд.
_МАРКЕТИНГ = re.compile(r"\b(?:comfort|elegan|stylish|perfect|beaut|suitab|ideal|trend|fashion|"
                        r"luxur|cozy|cosy|versatil|chic|flatter|feminin|romantic|modern|timeless|"
                        r"everyday|daily|casual|office|holiday|occasion|combin|easy|quality|"
                        r"premium|refined|unique|special|lovely|basic|essential|effortless|"
                        r"aesthetic|refresh|statement|must\-have)\w*", re.I)
# «relaxed» НЕ в переліку вище, хоч і стояло там до РЗ-1: це КОД крою (`каталог_розбір.КРІЙ`), і
# «relaxed fit» — посадка, яку правило §3 дозволяє прямо. Огляд 40 рядків очима (сід 29) дав його
# єдиною хибною тривогою маркетингу з 27 — ж-07075 «relaxed fit, high waist, straight legs».
_РОЗМІР = re.compile(r"\b(?:sizes?|measurement\w*|\d+(?:[.,]\d+)?\s*(?:cm|mm|inch\w*)|cm|mm)\b", re.I)
# ВИНЯТОК, НАЗВАНИЙ САМИМ ПРАВИЛОМ К-5: «висота каблука — не обмір тіла чи речі під розмір, а
# форма взуття: вона лишається». Тому сантиметри ПРИ КАБЛУКУ чи платформі не заборона. Огляд 40
# рядків очима (сід 29): з 7 тривог «розмір» дві були саме цим («8 cm block heel», «10 cm heel»).
_КАБЛУК_У_СМ = re.compile(r"(?:heel|platform)[^,;.]{0,20}?\d+(?:[.,]\d+)?\s*(?:cm|mm)"
                          r"|\d+(?:[.,]\d+)?\s*(?:cm|mm)[^,;.]{0,20}?(?:heel|platform)", re.I)
_КРАЇНА = re.compile(r"\b(?:made|manufactured|produced|sewn|handmade)\s+in\b|\bcountry of origin\b", re.I)
_ЦІНА = re.compile(r"\b(?:uah|usd|eur|\u0433\u0440\u043d|price)\b|[$\u20ac\u20b4]", re.I)
_ДОГЛЯД = re.compile(r"\b(?:dry\s?clean|machine\s?wash|hand\s?wash|do not\s+\w+|tumble|"
                     r"iron(?:ing)?|bleach|care instructions?)\b", re.I)
_ВІДГУК = re.compile(r"\b(?:customers?|buyers?|reviews?|recommend\w*|loved by|bestsell\w*|"
                     r"popular)\b", re.I)
СКЛАД_ТКАНИНИ = re.compile(r"\b(?:\d{1,3}\s*%|cotton|viscose|wool|linen|silk|polyester|elastane|"
                           r"cashmere|acrylic|polyamide|leather)\b", re.I)
# Колір — тими самими словами, які код УЖЕ несе кодом `color_main`, плюс самі слова «колір».
_КОЛІР = re.compile(r"\b(?:%s)\b" % "|".join(sorted(
    re.escape(с) for с in set(КР.ПЕРЕЛІКИ["color_main"]) - {КР.UNKNOWN}
    | {"colour", "color", "shade", "tone"})), re.I)
_ВСІ_КОДИ = {с for к in КР.ПЕРЕЛІКИ.values() for код in к for с in re.split(r"[_\-]", код)}
# Порядок — порядок аркуша проби; «склад тканини» СВІДОМО не заборона, а окремий вимір.
ЗАБОРОНИ = ("маркетинг", "розмір", "бренд", "колір", "країна", "ціна", "догляд", "відгук")
_ЗА_РЕГІСТРОМ = {"маркетинг": _МАРКЕТИНГ, "розмір": _РОЗМІР, "колір": _КОЛІР, "країна": _КРАЇНА,
                 "ціна": _ЦІНА, "догляд": _ДОГЛЯД, "відгук": _ВІДГУК}


def бренд_у_рядку(рядок, дані, ід):
    """Збіг бренду в рядку або None — тією ж міркою, що `проби/каталог_розбір_нюанси.py`: ім'я з
    великої літери з ДАНИХ крамниці, що не є кодом, або ім'я самої крамниці з id. Інакше «English
    collar» і «The style» читались би брендом."""
    імена = [і for і in re.findall(r"\b[A-Z][A-Za-z]{2,}(?: [A-Z][A-Za-z]{2,})*",
                                  json.dumps(дані, ensure_ascii=False))
             if і.lower() not in _ВСІ_КОДИ]
    крамниця = ід.split("@")[-1].split(".")[0]
    return (next((re.search(re.escape(і), рядок) for і in імена if і in рядок), None)
            or re.search(r"\b%s\b" % re.escape(крамниця), рядок, re.I))


def заборони_рядка(рядок, дані, ід):
    """Рядок `features` → [(код заборони, збіг)] у порядку `ЗАБОРОНИ`. Порожній список = чисто."""
    вих = []
    for к in ЗАБОРОНИ:
        з = бренд_у_рядку(рядок, дані, ід) if к == "бренд" else _ЗА_РЕГІСТРОМ[к].search(рядок)
        if к == "розмір" and з and _КАБЛУК_У_СМ.search(рядок[max(0, з.start() - 24):з.end() + 24]):
            з = _РОЗМІР.search(_КАБЛУК_У_СМ.sub(" ", рядок))
        if з:
            вих.append((к, з.group(0)))
    return вих


def розділити(текст):
    """Файл речі → (дані запиту без «завдання», рядок відповіді). Порожній dict, коли запиту нема."""
    запит, _, відп = текст.replace("\r\n", "\n").partition("\n\n\u2500\u2500 \u0412\u0406\u0414\u041f\u041e\u0412\u0406\u0414\u042c")
    запит = запит.split("\u2500\u2500 \u0417\u0410\u041f\u0418\u0422\n", 1)[-1]
    try:
        дані = {к: в for к, в in json.loads(запит).items() if к != "завдання"}
    except Exception:                                # noqa: BLE001 — запиту нема, бренд не звірити
        дані = {}
    return дані, відп


# ── ПОРУШНИКИ: КОГО ПЕРЕПИТУВАТИ (РЗ-1) ─────────────────────────────────────
# Групи прогону — це слоти внутрішньої мови; модель відповідає кодом того самого слота. Розбіжність
# між ними — не «інший відтінок думки», а інша річ: ж-07754 стоїть у групі «сукня», а модель
# сказала `slot: headwear` і `item_type: beret`. Такий розбір нікуди не годиться цілий.
СЛОТ_ГРУПИ = dict([(ВМ.ТАБЛИЦЯ["slot"][к], (к,)) for к in ("top", "bottom", "dress", "outerwear",
                                                           "shoes", "bag")]
                  + [("прикраси", tuple(к for к, в in ВМ.ТАБЛИЦЯ["slot"].items()
                                        if в in ПРИКРАСИ)),
                     ("дрібне", tuple(к for к, в in ВМ.ТАБЛИЦЯ["slot"].items() if в in ДРІБНЕ))])
ПОРУШНИКИ_ФАЙЛ = "порушники.txt"
# Коди причин (не слова для людини): рядок файла — «<id> <коди через кому>».
ПРИЧИНА_ЗАБОРОНА, ПРИЧИНА_НЕМА, ПРИЧИНА_СЛОТ = "features_ban", "features_none", "slot_vs_group"


def слот_проти_групи(поля, група):
    """Слот моделі суперечить групі прогону (`СЛОТ_ГРУПИ`; `unknown` не суперечить). ОДИН критерій на
    `порушники` і `підставити`: інакше повтор брав би відповідь, яка й далі суперечить групі, — а
    порушником її позначила б наступна лічба."""
    дозволені = СЛОТ_ГРУПИ.get(група)
    return bool(дозволені) and поля["slot"] not in дозволені + (КР.UNKNOWN,)



def порушники(тека):
    """Тека прогону → `порушники.txt` (id + коди причин) і словник {id: [коди]}; повертає шлях.

    Порушник — річ, чий розбір треба перепитати, і тільки вона: рядок `features` із забороною
    (`заборони_рядка`), рядка `features` НЕМА зовсім (unknown, нема поля, відповідь не JSON) або
    слот моделі суперечить групі прогону (`СЛОТ_ГРУПИ`). Решта каталогу моделі вдруге не
    коштує: на 8 850 речах прогону порушників 3 970 (45 %), тобто повтор — 13 годин карти
    замість 30. ЧЕСНО ПРО `slot_vs_group`: огляд очима показав, що в частині випадків помиляється
    не модель, а ГРУПА коду (ж-11523, ж-11515 — очевидні крос-боді в групі «верх», модель сказала
    `bag` правильно). Повтор таких речей нічого не змінить; знахідка — рядком дошки."""
    with open(os.path.join(тека, "прогін.json"), encoding="utf-8") as ф:
        речі = json.load(ф)["речі"]
    чому, лічба = {}, collections.Counter()
    for р in речі:
        шлях = os.path.join(тека, р["файл"])
        if not os.path.exists(шлях):
            continue
        with open(шлях, encoding="utf-8") as ф:
            дані, відп = розділити(ф.read())
        поля, _ = КР.з_відповіді(відп)
        коди = []
        if поля is None or поля[КР.ОСОБЛИВОСТІ] == КР.UNKNOWN:
            коди.append(ПРИЧИНА_НЕМА)
        else:
            коди += [ПРИЧИНА_ЗАБОРОНА + ":" + к
                     for к, _ in заборони_рядка(поля[КР.ОСОБЛИВОСТІ], дані, р["id"])]
        if поля is not None and слот_проти_групи(поля, р["група"]):
            коди.append(ПРИЧИНА_СЛОТ)
        if коди:
            чому[р["id"]] = коди
            for к in коди:
                лічба[к.split(":")[0]] += 1
    шлях = os.path.join(тека, ПОРУШНИКИ_ФАЙЛ)
    with open(шлях, "w", encoding="utf-8") as ф:
        for ід in sorted(чому):
            ф.write("%s %s\n" % (ід, ",".join(чому[ід])))
    print("порушники: %s · речей %d з %d (%.1f %%) · %s · повтор ~%.1f год при 12 с/річ"
          % (шлях, len(чому), len(речі), 100.0 * len(чому) / max(len(речі), 1),
             " ".join("%s %d" % (к, н) for к, н in sorted(лічба.items())),
             len(чому) * 12.0 / 3600))
    return шлях


def зібрати(тека):
    """ЗБИРАЧ: тека прогону → `розбір.json` у тій самій теці; повертає його шлях.

    ФОРМА (з неї наряд К-3 будує короткий запис речі в пулі; ключі кодів — ті самі, що дає
    `каталог_розбір.з_відповіді`, тобто шляхи `каталог_розбір.ПОЛЯ`):
      {"<id офера>": {коди: "slot", "item_type", …, "veto": {…}; і "features": "<рядок>"},
       …,
       "причини": {"<id офера>": ["<причина>", …]}}
    Під `ПРИЧИНИ` — лише речі, що причини мають: вади форми відповіді й рядка особливостей
    (`з_відповіді`) і впалий виклик. Річ, чия відповідь не JSON або чий виклик упав, полів не має —
    під її id нічого, є лише її причини. Нічого мовчки."""
    with open(os.path.join(тека, "прогін.json"), encoding="utf-8") as ф:
        мірка = json.load(ф)
    вих, причини = {}, {}
    for р in мірка["речі"]:
        with open(os.path.join(тека, р["файл"]), encoding="utf-8") as ф:
            поля, пр = КР.з_відповіді(ф.read().split("── ВІДПОВІДЬ", 1)[-1])
        if р.get("впало"):
            пр = ["виклик упав: %s" % р["впало"]] + пр
        if поля is not None:
            вих[р["id"]] = поля
        if пр:
            причини[р["id"]] = пр
    вих[ПРИЧИНИ] = причини
    шлях = os.path.join(тека, "розбір.json")
    with open(шлях, "w", encoding="utf-8") as ф:
        json.dump(вих, ф, ensure_ascii=False, indent=1)
    рядки = sum(1 for к, п in вих.items() if к != ПРИЧИНИ and п[КР.ОСОБЛИВОСТІ] != КР.UNKNOWN)
    print("розбір: %s · речей з полями %d з %d · features не unknown %d · речей з причинами %d"
          % (шлях, len(вих) - 1, len(мірка["речі"]), рядки, len(причини)))
    return шлях


# Підсумки підстановки — КОДАМИ, не словами (п.12 і сканер контрактів: рядковий ключ-слово в
# індексі читається як поле фіду й вилазить «полем-сиротою»).
НЕМА_ФАЙЛА, НЕ_JSON, БЕЗ_РЯДКА = "no_file", "not_json", "no_features"
ЗАБОРОНА_ЛИШИЛАСЬ, СЛОТ_ЛИШИВСЯ, УЗЯТО = "ban_left", "slot_left", "taken"


def підставити(тека_повтору, тека):
    """Чисті відповіді повтору — у `розбір.json` теки прогону; брудні НЕ беруться. Повертає лічбу.

    ЧИСТО = те саме, що в пробі: відповідь розбирається як JSON, рядок `features` є (не unknown) і
    `заборони_рядка` порожній і слот моделі не суперечить групі прогону (`слот_проти_групи`: нова
    відповідь, що й далі суперечить групі, — та сама хиба, її брати не можна). Інакше під id лишається СТАРИЙ розбір — повтор може бути гірший за
    перший раз, і мовчки погіршити каталог він не має права. Причини речі переписуються разом з
    полями (вони від тієї самої відповіді), і до них додається рядок «повтор: узято» — щоб потім
    було видно, звідки взявся цей розбір."""
    with open(os.path.join(тека_повтору, "прогін.json"), encoding="utf-8") as ф:
        речі = json.load(ф)["речі"]
    шлях = os.path.join(тека, "розбір.json")
    with open(шлях, encoding="utf-8") as ф:
        розбір = json.load(ф)
    лічба = collections.Counter()
    for р in речі:
        ф_шлях = os.path.join(тека_повтору, р["файл"])
        if not os.path.exists(ф_шлях):
            лічба[НЕМА_ФАЙЛА] += 1
            continue
        with open(ф_шлях, encoding="utf-8") as ф:
            дані, відп = розділити(ф.read())
        поля, пр = КР.з_відповіді(відп)
        if поля is None:
            лічба[НЕ_JSON] += 1
        elif поля[КР.ОСОБЛИВОСТІ] == КР.UNKNOWN:
            лічба[БЕЗ_РЯДКА] += 1
        elif заборони_рядка(поля[КР.ОСОБЛИВОСТІ], дані, р["id"]):
            лічба[ЗАБОРОНА_ЛИШИЛАСЬ] += 1
        elif слот_проти_групи(поля, р["група"]):
            лічба[СЛОТ_ЛИШИВСЯ] += 1
        else:
            розбір[р["id"]] = поля
            розбір[ПРИЧИНИ][р["id"]] = пр + ["повтор: узято"]
            лічба[УЗЯТО] += 1
    with open(шлях, "w", encoding="utf-8") as ф:
        json.dump(розбір, ф, ensure_ascii=False, indent=1)
    print("підстановка: %s · речей повтору %d · %s"
          % (шлях, len(речі), " · ".join("%s %d" % (к, н) for к, н in sorted(лічба.items()))))
    return лічба


