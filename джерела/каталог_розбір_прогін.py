# іде виклик, — `loaded_context_length` завантаженої моделі (`_вікно_рушія`), поділене на слоти прогону (LM Studio ділить
# контекст на `--parallel`, див. `ПАРАЛЕЛЬНО`); (2) міряє токени всього промпта (`пакет_моделі.токенів` × поправка з
# `prompt_tokens` попереднього виклику цієї моделі) разом зі стелею виводу; (3) не влазить — скорочує за метою: опис
# крамниці тримає хіба цілі речення зі свого початку (хвіст — доставка, оплата, чужі товари: правило промпта), назва й
# картка лишаються; і так не влазить — виняток `prompt_exceeds_model_window` з числами ДО виклику, річ іде в «впало» з
# названою причиною. Не символи: речення знімаються по одному, поки не влізе. Вікна не знаємо (LM Studio мовчить, модель
# не завантажена) — не міряємо, як і хмарна модель у показі. Скорочення видно в годиннику (`скорочено_речень`) і в stderr.
ПОПРАВКА_ТОКЕНІВ_ПОЧАТКОВА = 1.0         # нема виміру рушія для цієї моделі: оцінку не зменшуємо
_ВІКНА, _ПОПРАВКИ = {}, {}
_РЕЧЕННЯ = re.compile(r"(?<=[.!?\u2026\n])")


def _вікно_рушія(ід_моделі):
    """Контекст завантаженої моделі (токени) з налаштування LM Studio: `loaded_context_length` у `/api/v0/models`;
    0 — вікна не знаємо (сервер не відповів, моделі в пам'яті нема)."""
    if ід_моделі not in _ВІКНА:
        try:
            with urllib.request.urlopen(АДРЕСА.rsplit("/v1", 1)[0] + "/api/v0/models", timeout=15) as в:
                моделі = json.load(в).get("data", [])
        except Exception:                             # noqa: BLE001 — нема відповіді = вікна не знаємо
            return 0
        for м in моделі:
            if м.get("id") == ід_моделі and м.get("state") == "loaded":
                _ВІКНА[ід_моделі] = int(м.get("loaded_context_length") or 0)
    return _ВІКНА.get(ід_моделі, 0)


def _оцінка_промпта(тіло):
    """Токени всіх повідомлень тіла за вагою знаків Qwen (без поправки рушія)."""
    return sum(оцінка_токенів(п["content"]) for п in тіло["messages"])


def _вмістити_у_вікно(тіло, слотів=1):
    """(тіло, запис для годинника): промпт разом зі стелею виводу влазить у вікно слота моделі — або це тіло з
    скороченим описом речі, або виняток `prompt_exceeds_model_window`. Вікна не знаємо — тіло як є, запис порожній."""
    вікно = _вікно_рушія(тіло.get("model")) // max(слотів, 1)
    if not вікно:
        return тіло, {}
    стеля, поправка = тіло.get("max_tokens") or 0, _ПОПРАВКИ.get(тіло.get("model"), ПОПРАВКА_ТОКЕНІВ_ПОЧАТКОВА)
    сира = _оцінка_промпта(тіло)
    токенів = math.ceil(сира * поправка)
    запис = dict(вікно=вікно, стеля_виводу=стеля, оцінка_сира_т=сира, оцінка_до_т=токенів, скорочено_речень=0)
    if токенів + стеля > вікно:
        тіло = dict(тіло, messages=[dict(п) for п in тіло["messages"]])
        дані = None
        try:
            дані = json.loads(тіло["messages"][-1]["content"])
        except ValueError:
            pass
        опис = дані.get("description") if isinstance(дані, dict) else None
        речення = _РЕЧЕННЯ.split(опис) if isinstance(опис, str) else []
        while речення and токенів + стеля > вікно:
            речення.pop()
            дані["description"] = "".join(речення)
            тіло["messages"][-1]["content"] = json.dumps(дані, ensure_ascii=False)
            запис["скорочено_речень"] += 1
            сира = _оцінка_промпта(тіло)
            токенів = math.ceil(сира * поправка)
        запис["оцінка_сира_т"] = сира                 # поправка рушія вчиться з тіла, що пішло, не з повного (11738)
        if токенів + стеля > вікно:
            raise ValueError("prompt_exceeds_model_window · tokens≈%d + max_tokens=%d > window=%d (слот) · описом речі не виправити"
                             % (токенів, стеля, вікно))
        print("промпт скорочено до вікна: опис без %d останніх речень · tokens≈%d→%d + max_tokens=%d ≤ window=%d"
              % (запис["скорочено_речень"], запис["оцінка_до_т"], токенів, стеля, вікно), file=sys.stderr)
    запис["оцінка_т"] = токенів
    return тіло, запис


def _обрив(е):
    """Чи виняток — обрив з'єднання (сервер не відповів), а не відповідь сервера з кодом HTTP."""
    if isinstance(е, urllib.error.HTTPError):
        return False
    return isinstance(е, (ConnectionError, socket.timeout, TimeoutError, urllib.error.URLError))


def надіслати(тіло, годинник=None, стадія="річ"):
    """(текст відповіді, секунд) — від сервера моделі форми OpenAI (`АДРЕСА`, MODEL_URL); кожна спроба — у
    `годинник`. Швидкий обрив з'єднання — один повтор із причиною `connection_reset` (`ОБРИВ_ШВИДКИЙ_С`);
    решта винятків — вгору, як доти. Одна дорога для прогонів А і Б (`прилади/розбір_рядків_5192.py`)."""
    тіло, у_вікні = _вмістити_у_вікно(тіло, годинник.паралельно if годинник else 1)
    дані = json.dumps(тіло, ensure_ascii=False).encode("utf-8")
    for спроба in range(2):
        запис = dict(у_вікні, стадія=стадія, спроба=спроба, т0=time.time())
        try:
            запит = urllib.request.Request(АДРЕСА + "/chat/completions", data=дані,
                                           headers={"Content-Type": "application/json"})
            with urllib.request.urlopen(запит, timeout=3600) as в:
                відп = json.loads(в.read().decode("utf-8"))
        except Exception as е:                        # noqa: BLE001 — спробу названо в годиннику, виняток іде вгору
            запис.update(т1=time.time(), обрив=_обрив(е), помилка="%s: %s" % (type(е).__name__, е))
            повтор = запис["обрив"] and not спроба and запис["т1"] - запис["т0"] <= ОБРИВ_ШВИДКИЙ_С
            if повтор:
                запис["причина"] = "connection_reset"
            if годинник:
                годинник.записати(запис)
            if not повтор:
                raise
            time.sleep(2 + 2 * random.random())
            continue
        вжито = відп.get("usage") or {}
        if у_вікні and вжито.get("prompt_tokens"):
            _ПОПРАВКИ[тіло.get("model")] = вжито["prompt_tokens"] / max(у_вікні["оцінка_сира_т"], 1)
        запис.update(т1=time.time(), вхід_т=вжито.get("prompt_tokens") or 0, вихід_т=вжито.get("completion_tokens") or 0)
        if годинник:
            годинник.записати(запис)
        вибір = (відп.get("choices") or [{}])[0]
        return ((вибір.get("message") or {}).get("content") or ""), round(запис["т1"] - запис["т0"], 1)


def модель(промпт, ід_моделі, сід=None, схема=True, годинник=None):
    """(текст відповіді, секунд) від локальної моделі форми OpenAI; виняток — вгору, його пише
    прогін у файл речі, а не ковтає. `схема` — граматика відповіді (`response_format` зі
    `КР.схема_відповіді`); `сід` — для повтору: той самий промпт, інша вибірка токенів;
    `годинник` — спроби в годинник прогону (`надіслати`)."""
    тіло = dict(model=ід_моделі, messages=[dict(role="user", content=промпт)], stream=False,
                max_tokens=int(os.environ.get("MODEL_MAX_TOKENS") or МАКС_ТОКЕНІВ))
    if схема and not _ГРАМАТИКА["не_бере"]:
        тіло["response_format"] = {"type": "json_schema", "json_schema": {
            "name": ІМ_СХЕМИ, "strict": True, "schema": КР.схема_відповіді()}}
    if os.environ.get("MODEL_TEMP"):
        тіло["temperature"] = float(os.environ["MODEL_TEMP"])
    if сід is not None:
        тіло["seed"] = сід
    try:
        return надіслати(тіло, годинник)
    except urllib.error.HTTPError as е:
        if "response_format" not in тіло or е.code not in (400, 422):
            raise
        # `response_format` — ЛИШЕ ПРИСКОРЕННЯ, НЕ УМОВА (наряд Е2-межі-поза-реєстром; стилісткою може бути будь-яка
        # модель, власник 27.10): сервер, що його не бере, доти валив КОЖНУ річ прогону. Та сама річ — без нього;
        # пройшло — решта прогону теж без нього, а форму тримає реєстр (`з_відповіді`) і повтор словами. Впало й
        # без нього (переповнений слот — та сама 400) — виняток вгору, як доти.
        del тіло["response_format"]
        відповідь = надіслати(тіло, годинник, стадія="річ_без_граматики")
        if not _ГРАМАТИКА["не_бере"]:
            _ГРАМАТИКА["не_бере"] = True
            print("сервер не взяв response_format (HTTP %d) — далі без граматики відповіді" % е.code, file=sys.stderr)
        return відповідь


# Сервер відкинув `response_format` (HTTP 400/422) і взяв ту саму річ без нього — решта прогону без нього (`модель`).
_ГРАМАТИКА = {"не_бере": False}


def _спитати(повід, ід_моделі, схема=True, годинник=None):
    """(відповідь, секунд усього, впало, повторів) — з `ПОВТОРІВ_НА_НЕ_JSON` повторами (іншим
    сідом і з розбіжністю словами), поки відповідь не розбирається як JSON. Беремо ПЕРШУ, що розібралась; коли жодна —
    першу, щоб у файлі лишилось те, що модель сказала. Впалий виклик (мережа, сервер) повтором
    не лікується — його названо окремо."""
    перша, секунд, спроба, запит = None, 0.0, 0, повід
    for спроба in range(1 + ПОВТОРІВ_НА_НЕ_JSON):
        try:
            текст, с = модель(запит, ід_моделі, спроба or None, схема, годинник)
        except Exception as е:                        # noqa: BLE001 — впалий виклик названий
            return перша or "", round(секунд, 1), "%s: %s" % (type(е).__name__, е), спроба
        секунд += с
        перша = текст if перша is None else перша
        розбір, причини = КР.з_відповіді(текст)
        if розбір is not None:
            return текст, round(секунд, 1), None, спроба
        запит = СВ.СХЕМИ_ВІДПОВІДІ["КАТАЛОГ_РІЧ"].промпт_повтору(повід, причини[-1])
    return перша or "", round(секунд, 1), None, спроба


def ід_еталону(шлях):
    """id речей з файла еталону: JSON-список (рядків чи обʼєктів з «id»), JSON-обʼєкт (ключі-id
    або список під «речі»/«items»), чи текст — id першим словом рядка. Форму еталону РЗ-Е пише
    паралельна сесія, тож читається будь-яка з цих — порядком файла."""
    with open(шлях, encoding="utf-8") as ф:
        сире = ф.read()
    try:
        дані = json.loads(сире)
    except ValueError:
        return [р.split()[0] for р in сире.splitlines() if р.strip() and not р.startswith("#")]
    if isinstance(дані, dict):
        дані = next((дані[к] for к in ("речі", "items", "еталон") if isinstance(дані.get(к), list)),
                    [к for к in дані if "@" in к])
    return [д["id"] if isinstance(д, dict) else str(д) for д in дані
            if not isinstance(д, dict) or д.get("id")]


def група_речі(o, слот):
    """Перша група `ГРУПИ`, що бере річ, або «решта» — як у `вибірка`."""
    return next((ім for ім, _, підходить in ГРУПИ if підходить(o, слот)), "решта")


def _готова(шлях, повід):
    """Відповідь із файла попереднього запуску — коли ЗАПИТ у ньому той самий знак у знак (та сама
    річ, те саме правило) і відповідь не порожня; інакше None, і річ іде в модель. Інше правило —
    інший запит, тож відповіді двох правил в одній теці так не змішаються."""
    if not os.path.exists(шлях):
        return None
    with open(шлях, encoding="utf-8") as ф:
        запит, _, відп = ф.read().partition("\n\n── ВІДПОВІДЬ\n")
    відп = відп[:-1] if відп.endswith("\n") else відп
    return відп if запит == "── ЗАПИТ\n" + повід and відп.strip() else None


def _записати(куди, мірка):
    """`прогін.json` — через тимчасовий файл і заміну: обірваний запис не псує попередній."""
    шлях = os.path.join(куди, "прогін.json")
    with open(шлях + ".tmp", "w", encoding="utf-8") as ф:
        json.dump(мірка, ф, ensure_ascii=False, indent=1)
    os.replace(шлях + ".tmp", шлях)


def прогін(ід_моделі, мова=КР.МОВА, куди=None, на_групу=НА_ГРУПУ, сід=СІД, усі=False, ті_самі=None,
           паралельно=ПАРАЛЕЛЬНО, еталон=None, нових=0, схема=True):
    """Вибірку — через модель у теку. Один файл на річ («── ЗАПИТ», «── ВІДПОВІДЬ»), плюс
    `прогін.json` з міркою кожного виклику. Повертає шлях теки.

    `усі` — ПОВНИЙ КАТАЛОГ: кожна група цілком, а речі, яких жодна група не взяла, — групою
    «решта» (на `каталог_повний.xml` 27.09 — 3 з 11 993: слот коду поза групами). Річ, що вже має
    відповідь у теці під тим самим запитом (`_готова`) і в мірці попереднього запуску, у модель
    вдруге не йде — так перерваний прогін докатується тією самою командою.

    `ті_самі` — тека попереднього прогону: ті самі речі в тих самих групах і тому самому порядку.
    ЧОМУ НЕ СІД. Вибірка тим самим сідом на main 27.09 — уже НЕ ті 300 речей, що прогнав ноутбук
    на f02325e: спільних id 158 з 300 (між цими комітами змінилось читання каталогу —
    `фід_каталог`, `фід_розбір`, — а з ним пули груп). «До/після» правила на різних речах
    міряло б різницю вибірок, а не правила.

    `еталон` (РЗ-К, пілот) — файл id еталону очима (`ід_еталону`): ці речі першими, а за ними
    `нових` речей, яких в еталоні нема, — `вибірка` сідом `сід` по ⌈нових/10⌉ на групу. Еталон
    міряє правдивість кодів, нові — що правило не підігнане під еталон.
    `паралельно` — скільки запитів водночас (`ПАРАЛЕЛЬНО`); `схема` — граматика відповіді."""
    офери, _ = ФР.читати_yml(ФК.каталог_на_диску(), показ=False)
    за_ід = {o["id"]: o for o in офери}
    if еталон:
        ід = [і for і in ід_еталону(еталон) if і in за_ід]
        слоти = {}
        for і in ід:
            try:
                слоти[і] = ФС.слот(за_ід[і])
            except Exception:                         # noqa: BLE001 — падіння слота теж вибірка
                слоти[і] = None
        пари = [("еталон_" + група_речі(за_ід[і], слоти[і]), за_ід[і]) for і in ід]
        решта = [o for o in офери if o["id"] not in set(ід)]
        пари += вибірка(решта, -(-нових // len(ГРУПИ)), сід)[:нових] if нових else []
        print("еталон %s: %d речей у каталозі · нових %d" % (еталон, len(ід), len(пари) - len(ід)))
    elif ті_самі:
        with open(os.path.join(ті_самі, "прогін.json"), encoding="utf-8") as ф:
            взірець = json.load(ф)["речі"]
        пари = [(р["група"], за_ід[р["id"]]) for р in взірець if р["id"] in за_ід]
        print("ті самі речі, що в %s: %d з %d (решти в каталозі на диску нема)"
              % (ті_самі, len(пари), len(взірець)))
    else:
        пари = вибірка(офери, len(офери) if усі else на_групу, сід)
    if усі and not ті_самі and not еталон:
        взяті = {o["id"] for _, o in пари}
        пари += [("решта", o) for o in офери if o["id"] not in взяті]
    куди = куди or os.path.join(ТУТ, "..", "аудит", "розбір_каталогу",
                                "%s_%s" % (ід_моделі.replace("/", "_"), мова))
    os.makedirs(куди, exist_ok=True)
    було = {}
    if os.path.exists(os.path.join(куди, "прогін.json")):
        with open(os.path.join(куди, "прогін.json"), encoding="utf-8") as ф:
            було = {р["файл"]: р for р in json.load(ф).get("речі", []) if not р.get("впало")}
    мірка = dict(модель=ід_моделі, мова=мова, url=АДРЕСА, сід=сід, паралельно=паралельно,
                 граматика=bool(схема), макс_токенів=int(os.environ.get("MODEL_MAX_TOKENS")
                                                           or МАКС_ТОКЕНІВ),
                 на_групу=("еталон %s + нових %d" % (os.path.basename(еталон), нових) if еталон
                           else "як у %s" % os.path.basename(os.path.normpath(ті_самі)) if ті_самі
                           else "усі" if усі else на_групу),
                 задача=КР.РОЗБІР[мова].задача, речі=[])
    готові, чекають = {}, []
    for і, (група, o) in enumerate(пари, 1):
        # Компактний JSON (РЗ-К): відступи — це ~700 пробілів і переносів на запит, які модель
        # читає як токени, а не зміст (вимір у коміті).
        повід = json.dumps(КР.промпт(o, мова), ensure_ascii=False)
        ім = "%02d_%s_%s.txt" % (і, група, o["id"].replace("/", "_").replace("@", "_"))
        if ім in було and _готова(os.path.join(куди, ім), повід) is not None:
            готові[і] = було[ім]
        else:
            чекають.append((і, група, o, ім, повід))

    def _одна(робота):
        """Одна річ у моделі: файл на диск, рядок мірки назад. Іде в потоці, тож спільного не пише
        нічого — ні `мірка`, ні друку; ім'я файла їй уже дане, тож два потоки не беруться за один."""
        і, група, o, ім, повід = робота
        відп, секунд, впало, повторів = _спитати(повід, ід_моделі, схема, годинник)
        with open(os.path.join(куди, ім), "w", encoding="utf-8") as ф:
            ф.write("── ЗАПИТ\n%s\n\n── ВІДПОВІДЬ\n%s\n" % (повід, відп))
        return і, dict(файл=ім, id=o["id"], група=група, секунд=секунд, знаків_запиту=len(повід),
                       знаків_відповіді=len(відп), впало=впало, повторів=повторів)

    т0, годинник = time.time(), Годинник(паралельно)
    for край in range(0, len(чекають), ЗАПИС_КОЖНІ):
        пачка = чекають[край:край + ЗАПИС_КОЖНІ]
        if паралельно > 1:
            with concurrent.futures.ThreadPoolExecutor(max_workers=паралельно) as пул:
                вийшло = list(пул.map(_одна, пачка))
        else:
            вийшло = [_одна(р) for р in пачка]
        for (і, рядок), робота in zip(вийшло, пачка):
            готові[і] = рядок
            print("%2d/%d %-18s %-28s %5.1f с%s %s"
                  % (і, len(пари), робота[1], робота[2]["id"][:28], рядок["секунд"],
                     " ×%d" % (рядок["повторів"] + 1) if рядок["повторів"] else "   ",
                     рядок["впало"] or ""))
        мірка["речі"] = [готові[і] for і in sorted(готові)]
        _записати(куди, мірка)
    мірка["речі"] = [готові[і] for і in sorted(готові)]
    _записати(куди, мірка)
    впали = sum(1 for р in мірка["речі"] if р["впало"])
    повторено = sum(1 for р in мірка["речі"] if р.get("повторів"))
    хід = time.time() - т0
    print("тека: %s · речей %d · готових з попереднього запуску %d · впало викликів %d · повторів "
          "на не-JSON %d · паралельно %d · %.1f с/річ стіною (%d нових за %.1f хв) · лічба: "
          "проби/каталог_розбір_лічба.py"
          % (куди, len(пари), len(пари) - len(чекають), впали, повторено, паралельно,
             хід / max(1, len(чекають)), len(чекають), хід / 60))
    _годинник_у_теку(куди, годинник, {"річ": (len(чекають), len(офери))})
    зібрати(куди)
    return куди


def _годинник_у_теку(куди, годинник, одиниці):
    """`годинник.json` теки й рядок «ГОДИННИК»: зведення спроб за стадіями й прогноз на весь каталог (наряд 4.4).
    Без нових викликів (усе з попереднього запуску) прогнозу нема — темп міряє лише цей запуск."""
    з, п = годинник.зведення(), годинник.прогноз(одиниці)
    with open(os.path.join(куди, "годинник.json"), "w", encoding="utf-8") as ф:
        json.dump(dict(з, прогноз=п), ф, ensure_ascii=False, indent=1)
    д = з["дія"]
    print("ГОДИННИК · стінний %.1f с · викликів %d · спроб %d · обривів %d · повторів %s · токени %d/%d · "
          "паралельно %d · прогноз %s"
          % (д["стінний_с"], д["викликів"], д["спроб"], д["обривів"], д["повторів"] or 0, д["вхід_т"], д["вихід_т"],
             з["паралельно"], "; ".join("%s %d із %d — %.2f с/од. → %.1f год" % (ст, в["зроблено"], в["всього"],
                                                                                    в["с_на_одиницю"], в["годин"])
                                        for ст, в in п["стадії"].items()) or "нема (нових викликів не було)"))


# Службовий ключ `розбір.json` поруч з id оферів (id має вигляд «ж-…@крамниця» і збігтися з ним не
# може): причини кожної речі — окремо від її полів, щоб короткий запис речі з полів їх не захопив.
ПРИЧИНИ = "причини"
# Ключі рамки запиту (англійського й старого українського шаблону) — не дані речі.
_РАМКА = frozenset(("task", "завдання", "version", "версія"))


def розділити(текст):
    """Файл речі → (вхід моделі без рамки, відповідь). Вхід — те, що модель бачила, і в ньому
    сторож шукає цитати (`каталог_розбір.з_відповіді`). Запиту не JSON — порожній dict."""
    запит, _, відп = текст.replace("\r\n", "\n").partition("\n\n── ВІДПОВІДЬ\n")
    запит = запит.split("── ЗАПИТ\n", 1)[-1]
    try:
        дані = {к: в for к, в in json.loads(запит).items() if к not in _РАМКА}
    except (ValueError, AttributeError):
        дані = {}
    return дані, відп


# ── СЛОТ ПРОТИ ГРУПИ (РЗ-1): ГРУПА ПРОГОНУ — СЛОТ КОДУ, МОДЕЛЬ — СВІЙ СЛОТ ──────
# Розбіжність — не «інший відтінок думки», а інша річ: ж-07754 стоїть у групі «сукня», а модель
# сказала `slot: headwear`. ЧЕСНО: огляд очима показав, що часом помиляється не модель, а ГРУПА
# коду (ж-11523, ж-11515 — крос-боді в групі «верх», модель сказала `bag` правильно; рядок 350
# РЗ-1). Тому це рядок причини в `розбір.json`, а не вирок відповіді.
СЛОТ_ГРУПИ = dict([(ВМ.ТАБЛИЦЯ["slot"][к], (к,)) for к in ("top", "bottom", "dress", "outerwear",
                                                           "shoes", "bag")]
                  + [("прикраси", tuple(к for к, в in ВМ.ТАБЛИЦЯ["slot"].items()
                                        if в in ПРИКРАСИ)),
                     ("дрібне", tuple(к for к, в in ВМ.ТАБЛИЦЯ["slot"].items() if в in ДРІБНЕ))])
ПРИЧИНА_СЛОТ = "slot_vs_group"


def слот_проти_групи(поля, група):
    """Слот моделі суперечить групі прогону (`СЛОТ_ГРУПИ`; «еталон_<група>» — та сама група;
    `unknown` не суперечить)."""
    дозволені = СЛОТ_ГРУПИ.get(група.replace("еталон_", "", 1))
    return bool(дозволені) and поля["slot"] not in дозволені + (КР.UNKNOWN,)


def зібрати(тека):
    """ЗБИРАЧ: тека прогону → `розбір.json` у тій самій теці; повертає його шлях.

    ФОРМА (з неї наряд К-3 будує короткий запис речі в пулі; ключі кодів — ті самі, що дає
    `каталог_розбір.з_відповіді`, тобто шляхи `каталог_розбір.ПОЛЯ`):
      {"<id офера>": {коди: "slot", "item_type", …, "veto": {…}; і "features": "<рядок>"},
       …,
       "причини": {"<id офера>": ["<причина>", …]}}
    Під `ПРИЧИНИ` — лише речі, що причини мають: вади форми відповіді й рядка особливостей
    (`з_відповіді`), коди без цитати в тексті речі (`invented`, РЗ-К), слот проти групи прогону
    (`slot_vs_group`) і впалий виклик. Річ, чия відповідь не JSON або чий виклик упав, полів не
    має — під її id нічого, є лише її причини. Нічого мовчки.
    СТОРОЖ ЦИТАТ працює завжди: вхід моделі береться з того самого файла (`розділити`), тож
    відповідь звіряється рівно з тим текстом, який модель бачила. Відповіді v1/v2 (голі коди) тут
    чесно стають unknown — цитат у них нема."""
    with open(os.path.join(тека, "прогін.json"), encoding="utf-8") as ф:
        мірка = json.load(ф)
    вих, причини = {}, {}
    for р in мірка["речі"]:
        with open(os.path.join(тека, р["файл"]), encoding="utf-8") as ф:
            дані, відп = розділити(ф.read())
        поля, пр = КР.з_відповіді(відп, дані)
        if поля is not None and слот_проти_групи(поля, р["група"]):
            пр = пр + ["%s · group=%s · slot=%s" % (ПРИЧИНА_СЛОТ, р["група"], поля["slot"])]
        if р.get("впало"):
            пр = ["виклик упав: %s" % р["впало"]] + пр
        if поля is not None:
            вих[р["id"]] = поля
        if пр:
            причини[р["id"]] = пр
    вих[ПРИЧИНИ] = причини
    шлях = os.path.join(тека, "розбір.json")
    with open(шлях, "w", encoding="utf-8") as ф:
        json.dump(вих, ф, ensure_ascii=False, indent=1)
    рядки = sum(1 for к, п in вих.items() if к != ПРИЧИНИ and п[КР.ОСОБЛИВОСТІ] != КР.UNKNOWN)
    вигадано = sum(1 for пр in причини.values() for т in пр if т.startswith("invented"))
    print("розбір: %s · речей з полями %d з %d · features не unknown %d · речей з причинами %d · "
          "кодів і фрагментів без цитати (invented) %d"
          % (шлях, len(вих) - 1, len(мірка["речі"]), рядки, len(причини), вигадано))
    return шлях


