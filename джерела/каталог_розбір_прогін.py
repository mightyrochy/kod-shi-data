def вибірка(офери, на_групу=НА_ГРУПУ, сід=СІД):
    """[(група, офер)] — по `на_групу` з кожної групи, сідом `сід`. Річ, що підійшла до кількох
    груп, лишається в ПЕРШІЙ: вибірка не має мірити ту саму річ двічі."""
    слоти, взяті, вих = {}, set(), []
    for o in офери:
        try:
            слоти[o["id"]] = ФС.слот(o)
        except Exception:                             # noqa: BLE001 — падіння слота теж вибірка
            слоти[o["id"]] = None
    for ім, _, підходить in ГРУПИ:
        пул = [o for o in офери if o["id"] not in взяті and підходить(o, слоти[o["id"]])]
        пул.sort(key=lambda o: o["id"])               # сід без порядку нічого не важить
        обрані = random.Random("%s-%s" % (сід, ім)).sample(пул, min(на_групу, len(пул)))
        взяті.update(o["id"] for o in обрані)
        вих.extend((ім, o) for o in обрані)
    return вих


def модель(промпт, ід_моделі, сід=None, темп=None, макс=None):
    """(текст відповіді, секунд) від локальної моделі форми OpenAI; виняток — вгору, його пише
    прогін у файл речі, а не ковтає.

    `сід` і `темп` кладуться В ТІЛО запиту й перебивають MODEL_TEMP. Це те, чим повтор
    порушників (`--повтор`) відрізняється від першого разу: ПРОМПТ ЛИШАЄТЬСЯ ЗНАК У ЗНАК ТИМ
    САМИМ — інакше міряли б інше правило, — а міняється лише вибірка токенів. Без цього повтор
    був би марний: той самий промпт із тим самим сідом і температурою 0 дає ту саму відповідь.
    `макс` — своя стеля токенів виклику (чистка рядка, `МАКС_ТОКЕНІВ_РЯДКА`), інакше типова."""
    тіло = dict(model=ід_моделі, messages=[dict(role="user", content=промпт)], stream=False,
                max_tokens=макс or int(os.environ.get("MODEL_MAX_TOKENS") or МАКС_ТОКЕНІВ))
    if os.environ.get("MODEL_TEMP"):
        тіло["temperature"] = float(os.environ["MODEL_TEMP"])
    if темп is not None:
        тіло["temperature"] = темп
    if сід is not None:
        тіло["seed"] = сід
    запит = urllib.request.Request(АДРЕСА + "/chat/completions",
                                   data=json.dumps(тіло, ensure_ascii=False).encode("utf-8"),
                                   headers={"Content-Type": "application/json"})
    т0 = time.time()
    with urllib.request.urlopen(запит, timeout=3600) as в:
        дані = json.loads(в.read().decode("utf-8"))
    вибір = (дані.get("choices") or [{}])[0]
    текст = ((вибір.get("message") or {}).get("content") or "")
    return текст, round(time.time() - т0, 1)


def _спитати(повід, ід_моделі, сід=None, темп=None, макс=None):
    """(відповідь, секунд усього, впало, повторів) — з `ПОВТОРІВ_НА_НЕ_JSON` повторами, поки
    відповідь не розбирається як JSON. Беремо ПЕРШУ, що розібралась; коли жодна — першу, щоб у
    файлі лишилось те, що модель сказала насправді. Впалий виклик (мережа, сервер) повтором не
    лікується — він не JSON-вада, і його названо окремо."""
    перша, секунд, спроба = None, 0.0, 0
    for спроба in range(1 + ПОВТОРІВ_НА_НЕ_JSON):
        try:
            текст, с = модель(повід, ід_моделі,
                              None if сід is None else сід + спроба, темп, макс)
        except Exception as е:                        # noqa: BLE001 — впалий виклик названий
            return перша or "", round(секунд, 1), "%s: %s" % (type(е).__name__, е), спроба
        секунд += с
        if перша is None:
            перша = текст
        if КР.з_відповіді(текст)[0] is not None:
            return текст, round(секунд, 1), None, спроба
    return перша or "", round(секунд, 1), None, спроба


def _готова(шлях, повід):
    """Відповідь із файла попереднього запуску — коли ЗАПИТ у ньому той самий знак у знак (та сама
    річ, те саме правило) і відповідь не порожня; інакше None, і річ іде в модель. Інше правило —
    інший запит, тож відповіді двох правил в одній теці так не змішаються."""
    if not os.path.exists(шлях):
        return None
    with open(шлях, encoding="utf-8") as ф:
        запит, _, відп = ф.read().partition("\n\n── ВІДПОВІДЬ\n")
    відп = відп[:-1] if відп.endswith("\n") else відп
    return відп if запит == "── ЗАПИТ\n" + повід and відп.strip() else None


def _записати(куди, мірка):
    """`прогін.json` — через тимчасовий файл і заміну: обірваний запис не псує попередній."""
    шлях = os.path.join(куди, "прогін.json")
    with open(шлях + ".tmp", "w", encoding="utf-8") as ф:
        json.dump(мірка, ф, ensure_ascii=False, indent=1)
    os.replace(шлях + ".tmp", шлях)


# ПОВТОР ПОРУШНИКІВ (РЗ-1): що саме міняється, щоб відповідь МОГЛА стати іншою.
# Промпт не чіпаємо — інакше повтор міряв би інше правило, і «до/після» втратило б сенс. Міняємо
# лише вибірку токенів: свій `seed` на кожну річ і кожну спробу плюс невелика температура в ТІЛІ
# запиту. Нуль температури з тим самим сідом повторив би ту саму відповідь знак у знак, а надто
# велика температура зробила б рядок ще брудніший — 0.4 лишає відповідь дисциплінованою і все ж
# рухає семплер з тієї самої доріжки. Ціною помилки не ризикуємо: `--підставити` бере нову
# відповідь ЛИШЕ коли вона чиста, інакше лишає стару.
ТЕМПЕРАТУРА_ПОВТОРУ = 0.4
СІД_ПОВТОРУ = 900000
# Спосіб повтору (РЗ-2): за кодами причин (`завдання_повтору`) чи тим самим промптом, як у РЗ-1.
СПОСІБ_ТОЙ_САМИЙ, СПОСІБ_ЦІЛЬ = "same", "targeted"


def прогін(ід_моделі, мова="uk", куди=None, на_групу=НА_ГРУПУ, сід=СІД, усі=False, ті_самі=None,
           паралельно=ПАРАЛЕЛЬНО, повтор=None, спосіб=СПОСІБ_ЦІЛЬ, перелік=None):
    """Вибірку — через модель у теку. Один файл на річ («── ЗАПИТ», «── ВІДПОВІДЬ»), плюс
    `прогін.json` з міркою кожного виклику. Повертає шлях теки.

    `усі` — ПОВНИЙ КАТАЛОГ: кожна група цілком, а речі, яких жодна група не взяла, — групою
    «решта» (на `каталог_повний.xml` 27.09 — 3 з 11 993: слот коду поза групами). Річ, що вже має
    відповідь у теці під тим самим запитом (`_готова`) і в мірці попереднього запуску, у модель
    вдруге не йде — так перерваний прогін докатується тією самою командою.

    `ті_самі` — тека попереднього прогону: ті самі речі в тих самих групах і тому самому порядку.
    ЧОМУ НЕ СІД. Вибірка тим самим сідом на main 27.09 — уже НЕ ті 300 речей, що прогнав ноутбук
    на f02325e: спільних id 158 з 300 (між цими комітами змінилось читання каталогу —
    `фід_каталог`, `фід_розбір`, — а з ним пули груп). «До/після» правила на різних речах
    міряло б різницю вибірок, а не правила.

    `повтор` — тека прогону, чиїх порушників перепитати (`перелік` — інший файл порушників, напр.
    пілот на частині; типово `порушники.txt` тієї теки). `спосіб`: `СПОСІБ_ЦІЛЬ` — за кодами
    причин (`завдання_повтору`, РЗ-2); `СПОСІБ_ТОЙ_САМИЙ` — той самий промпт іншим сідом (РЗ-1)."""
    офери, _ = ФР.читати_yml(ФК.каталог_на_диску(), показ=False)
    лише, старі = None, {}
    if повтор:
        ті_самі = ті_самі or повтор
        лише = причини_з(перелік or os.path.join(повтор, ПОРУШНИКИ_ФАЙЛ))
        if спосіб == СПОСІБ_ЦІЛЬ:
            with open(os.path.join(повтор, "розбір.json"), encoding="utf-8") as ф:
                старі = json.load(ф)
        print("повтор порушників з %s: %d id · спосіб %s · температура %.1f, свій сід на річ"
              % (повтор, len(лише), спосіб, ТЕМПЕРАТУРА_ПОВТОРУ))
    if ті_самі:
        за_ід = {o["id"]: o for o in офери}
        with open(os.path.join(ті_самі, "прогін.json"), encoding="utf-8") as ф:
            взірець = json.load(ф)["речі"]
        пари = [(р["група"], за_ід[р["id"]]) for р in взірець if р["id"] in за_ід
                and (лише is None or р["id"] in лише)]
        print("ті самі речі, що в %s: %d з %d (решти в каталозі на диску нема)"
              % (ті_самі, len(пари), len(взірець)))
    else:
        пари = вибірка(офери, len(офери) if усі else на_групу, сід)
    if усі and not ті_самі:
        взяті = {o["id"] for _, o in пари}
        пари += [("решта", o) for o in офери if o["id"] not in взяті]
    куди = куди or (os.path.normpath(повтор) + "_повтор" if повтор else
                    os.path.join(ТУТ, "..", "аудит", "розбір_каталогу",
                                 "%s_%s" % (ід_моделі.replace("/", "_"), мова)))
    os.makedirs(куди, exist_ok=True)
    було, було_стіною = {}, 0.0
    if os.path.exists(os.path.join(куди, "прогін.json")):
        with open(os.path.join(куди, "прогін.json"), encoding="utf-8") as ф:
            попередня = json.load(ф)
        було = {р["файл"]: р for р in попередня.get("речі", []) if not р.get("впало")}
        було_стіною = попередня.get("секунд_стіною", 0.0)
    мірка = dict(модель=ід_моделі, мова=мова, url=АДРЕСА, сід=сід,
                 на_групу=("як у %s" % os.path.basename(os.path.normpath(ті_самі)) if ті_самі
                           else "усі" if усі else на_групу),
                 задача=КР.РОЗБІР[мова].задача, речі=[])
    if повтор:
        мірка["повтор_з"] = os.path.basename(os.path.normpath(повтор))
        мірка["температура"], мірка["сід_моделі"] = ТЕМПЕРАТУРА_ПОВТОРУ, СІД_ПОВТОРУ
        мірка["спосіб"] = спосіб
    готові, чекають = {}, []
    for і, (група, o) in enumerate(пари, 1):
        хід, макс = None, None
        if повтор and спосіб == СПОСІБ_ЦІЛЬ:
            хід, повід, макс = завдання_повтору(o, лише[o["id"]], старі.get(o["id"]), група, мова)
        else:
            повід = КР.промпт(o, мова)
        повід = json.dumps(повід, ensure_ascii=False, indent=1)
        ім = "%02d_%s_%s.txt" % (і, група, o["id"].replace("/", "_").replace("@", "_"))
        if ім in було and _готова(os.path.join(куди, ім), повід) is not None:
            готові[і] = було[ім]
        else:
            чекають.append((і, група, o, ім, повід, хід, макс))

    def _одна(робота):
        """Одна річ у моделі: файл на диск, рядок мірки назад. Іде в потоці, тож спільного не пише
        нічого — ні `мірка`, ні друку; ім'я файла їй уже дане, тож два потоки не беруться за один."""
        і, група, o, ім, повід, хід, макс = робота
        відп, секунд, впало, повторів = _спитати(
            повід, ід_моделі, СІД_ПОВТОРУ + і * 10 if повтор else None,
            ТЕМПЕРАТУРА_ПОВТОРУ if повтор else None, макс)
        with open(os.path.join(куди, ім), "w", encoding="utf-8") as ф:
            ф.write("── ЗАПИТ\n%s\n\n── ВІДПОВІДЬ\n%s\n" % (повід, відп))
        рядок = dict(файл=ім, id=o["id"], група=група, секунд=секунд, знаків_запиту=len(повід),
                     знаків_відповіді=len(відп), впало=впало, повторів=повторів)
        if повтор:
            рядок.update(причини=лише[o["id"]], хід=хід or ХІД_ПОВНИЙ)
        return і, рядок

    т0 = time.time()
    for край in range(0, len(чекають), ЗАПИС_КОЖНІ):
        пачка = чекають[край:край + ЗАПИС_КОЖНІ]
        if паралельно > 1:
            with concurrent.futures.ThreadPoolExecutor(max_workers=паралельно) as пул:
                вийшло = list(пул.map(_одна, пачка))
        else:
            вийшло = [_одна(р) for р in пачка]
        for (і, рядок), робота in zip(вийшло, пачка):
            готові[і] = рядок
            print("%2d/%d %-18s %-28s %5.1f с%s %s"
                  % (і, len(пари), робота[1], робота[2]["id"][:28], рядок["секунд"],
                     " ×%d" % (рядок["повторів"] + 1) if рядок["повторів"] else "   ",
                     рядок["впало"] or ""))
        мірка["речі"] = [готові[і] for і in sorted(готові)]
        мірка["секунд_стіною"] = round(було_стіною + time.time() - т0, 1)
        _записати(куди, мірка)
    мірка["речі"] = [готові[і] for і in sorted(готові)]
    мірка["секунд_стіною"] = round(було_стіною + time.time() - т0, 1)
    _записати(куди, мірка)
    впали = sum(1 for р in мірка["речі"] if р["впало"])
    повторено = sum(1 for р in мірка["речі"] if р.get("повторів"))
    хід = time.time() - т0
    print("тека: %s · речей %d · готових з попереднього запуску %d · впало викликів %d · повторів "
          "на не-JSON %d · паралельно %d · %.1f с/річ стіною (%d нових за %.1f хв) · лічба: "
          "проби/каталог_розбір_лічба.py"
          % (куди, len(пари), len(пари) - len(чекають), впали, повторено, паралельно,
             хід / max(1, len(чекають)), len(чекають), хід / 60))
    if повтор:
        підсумок_повтору(куди, повтор)
    else:
        зібрати(куди)
    return куди


