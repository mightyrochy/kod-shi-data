    р.add_argument("--на-групу", type=int, default=НА_ГРУПУ, dest="на_групу")
    р.add_argument("--усі", action="store_true",
                   help="повний каталог: кожна група цілком і решта; докат — та сама команда")
    р.add_argument("--сід", type=int, default=СІД)
    р.add_argument("--ті-самі", default=None, metavar="ТЕКА", dest="ті_самі",
                   help="ті самі речі й групи, що в прогін.json цієї теки (до/після правила)")
    р.add_argument("--зібрати", default=None, metavar="ТЕКА",
                   help="лише зібрати розбір.json з наявної теки прогону, без моделі")
    р.add_argument("--паралельно", type=int, default=ПАРАЛЕЛЬНО,
                   help="скільки запитів до моделі водночас (контекст слота — біля ПАРАЛЕЛЬНО)")
    р.add_argument("--еталон", default=None, metavar="ФАЙЛ",
                   help="речі еталону першими (файл id: JSON чи текст), за ними --нових")
    р.add_argument("--нових", type=int, default=0, help="скільки речей поза еталоном додати")
    р.add_argument("--без-граматики", action="store_true", dest="без_граматики",
                   help="не слати response_format (сервер, що його не знає)")
    р.add_argument("--експорт", metavar="ФАЙЛ", help="разом із --зібрати: файл кодів для продукту")
    р.add_argument("--сусіди", choices=С.РЕЖИМИ, default=None,
                   help="розбирати модель один раз: сусіди (рівні всі слова крамниці, крім кольору й розміру) беруть "
                        "відповідь представника, колір — коротким викликом: «значення» — на унікальне значення "
                        "кольору, «річ» — на річ")
    р.add_argument("--колір-проба", default=None, metavar="ТЕКА", dest="колір_проба",
                   help="лише короткі кольорові виклики на речах цієї теки, розібраних повністю (потрібні --модель, "
                        "--сусіди; --нових = скільки речей випадково)")
    а = р.parse_args()
    if а.зібрати:
        експортувати(а.зібрати, а.експорт) if а.експорт else зібрати(а.зібрати)
    elif а.експорт:
        р.error("--експорт потребує --зібрати")
    elif а.колір_проба:
        if not (а.модель and а.сусіди):
            р.error("--колір-проба потребує --модель і --сусіди")
        колір_проба(а.колір_проба, а.модель, а.сусіди, а.паралельно, а.нових or None, а.сід)
    elif not а.модель:
        sys.exit("без --модель (або MODEL=…) прогону не буває: модель — параметр заміру")
    else:
        прогін(а.модель, а.мова, а.куди, а.на_групу, а.сід, а.усі, а.ті_самі, а.паралельно,
               а.еталон, а.нових, not а.без_граматики, а.сусіди)
