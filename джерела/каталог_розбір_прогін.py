# -*- coding: utf-8 -*-
"""каталог_розбір_прогін.py — ПРОГІН РОЗБОРУ КАТАЛОГУ НА НОУТБУЦІ (LM Studio, OpenAI-сумісний).

ЩО РОБИТЬ. Бере вибірку речей із каталогу на диску, на кожну збирає промпт
(`каталог_розбір.промпт`), кличе локальну українську мовну модель і КЛАДЕ СИРУ ВІДПОВІДЬ У ФАЙЛ.
Наприкінці ЗБИРАЧ (`зібрати`) складає з сирих відповідей `розбір.json` — коди й рядок
особливостей кожної речі (форма — у докстрінгу `зібрати`); його можна перезібрати й окремо, без
моделі. Лічбу (валідний JSON, покриття полів, форма `features`, незгода з кодом) робить проба
`джерела/проби/каталог_розбір_лічба.py` — на збережених відповідях, уже без моделі: вимір має
перечитуватись без повторного прогону.

ЯК ЗАПУСТИТИ (ноутбук, LM Studio слухає 127.0.0.1:1234):
  python3 джерела/каталог_розбір_прогін.py --модель <ід моделі> [--мова uk|en] [--куди <тека>]
                                           [--на-групу 30]
  python3 джерела/каталог_розбір_прогін.py --зібрати <тека>        (лише `розбір.json`)
  python3 джерела/проби/каталог_розбір_лічба.py <тека>
  python3 аудит/проби/розбір_аркуш.py <тека MamayLM> <тека Lapa> <аркуш.html>   (фото + рядки)
Міряти на MamayLM і Lapa — «ми перевіряємо українські мовні моделі» (власник; НЕ gemma). Дві
мови промпта — два прогони в дві теки, і порівнюються числа проби, а не думки.
Змінні оточення (оболонка кириличних імен не має): MODEL_URL (типово http://127.0.0.1:1234/v1),
MODEL_TEMP, MODEL_MAX_TOKENS (типово 1500 — відповідь тут коротка: 30 полів і один рядок).

ВИБІРКА — ПО `--на-групу` НА ГРУПУ, СІД 17: типово 6 (60 речей Н-1), 30 — 300 речей перед
повним розбором (рішення власника 27.09). Вісім груп — сім'ї слотів, які код дає на цьому
каталозі; дві останні — прогалини, названі нарядом: набір (частини комплекту) і колір із кількох
слів. Кожна група стоїть тут із причиною, бо вибірка — це і є те, що вимір побачить.
ВИБІРКА 300 (перевірено 27.09 на `каталог_повний.xml`, 11 993 офери): 30 у кожній з 10 груп,
300 різних id, різні url і різні фото картки (`фід_фото.кадри_речі`; 12 речей фото картки не
мають); той самий сід — та сама вибірка. Дві речі з однією назвою (brenda.ua, хустки «з квітковим
принтом») — різні хустки: інші url і фото. Спільних із 60 речами Н-1 — 50: у восьми групах слотів
перші 6 речей ті самі, у «набір» — 2, у «колір_кілька_слів» — 0 (річ, узята раніше, виходить з
пулу наступних груп, а 30 знімають більше, ніж 6).
ЗНАХІДКА ПРО НАБІР (виміряно на `каталог_повний.xml`, 11 993 офери): `фід_слот.слот` не віддає
слота «комплект» НІ ОДНОГО разу, а поле збагачення «слот»=комплект стоїть лише на 7 речах —
тимчасом як PR #319 рахував 345→391 комплект. Тому набір тут відбирається СЛОВОМ назви
(`фід_слот._ТИПИ_НАБОРУ`: костюм, комплект, двійка, трійка, набір), а не слотом.
"""
import argparse
import json
import os
import random
import sys
import time
import urllib.request

ТУТ = os.path.dirname(os.path.abspath(__file__))
if ТУТ not in sys.path:
    sys.path.insert(0, ТУТ)

import каталог_розбір as КР          # noqa: E402
import фід_каталог as ФК             # noqa: E402
import фід_розбір as ФР              # noqa: E402
import фід_слот as ФС                # noqa: E402

# Ключ ЗОВНІШНЬОГО контракту: його пише не наш код, а оболонка оператора на ноутбуці.
# Декларація стоїть у модулі, а не в сканері (та сама конвенція, що в `каблук.ЗОВНІШНІ_ВХОДИ`):
# інакше `audit_contracts` рахує змінну оточення полем-сиротою — «читає, не пише ніхто».
ЗОВНІШНІ_ВХОДИ = {
 "MODEL_TEMP": "температура локальної моделі; без неї лишається та, що стоїть на сервері LM Studio",
}

СІД = 17
НА_ГРУПУ = 6
АДРЕСА = (os.environ.get("MODEL_URL") or "http://127.0.0.1:1234/v1").rstrip("/")
ПРИКРАСИ = ("прикраси", "сережки", "намисто", "браслет", "каблучка", "брошка", "кольє")
ДРІБНЕ = ("шарф", "головний_убір", "пояс")


def _слово_набору(o):
    """Чи назва речі каже про набір — тими самими словами, що їх знає код (`_ТИПИ_НАБОРУ`)."""
    низ = (o.get("назва") or "").lower()
    return any(с in низ for с in ФС._ТИПИ_НАБОРУ)


# (ім'я групи, що саме ця шестірка міряє, відбір речі)
ГРУПИ = (
    ("сукня", "довжина, виріз, рукав, крій", lambda o, с: с == "сукня"),
    ("верх", "крій, оверсайз і обтисле, тканина", lambda o, с: с == "верх"),
    ("низ", "крій, довжина, тканина", lambda o, с: с == "низ"),
    ("верхній_шар", "крій, тканина, оздоба", lambda o, с: с == "верхній_шар"),
    ("взуття", "каблук, халява, виріз стопи, матеріал верху", lambda o, с: с == "взуття"),
    ("сумка", "матеріал, метал фурнітури", lambda o, с: с == "сумка"),
    ("прикраси", "метал і «золотий» — тіло чи фурнітура", lambda o, с: с in ПРИКРАСИ),
    ("дрібне", "тканина хустки, метал пряжки", lambda o, с: с in ДРІБНЕ),
    ("набір", "set_kind і частини комплекту", lambda o, с: _слово_набору(o)),
    ("колір_кілька_слів", "color_main, color_extra, color_why, color_from",
     lambda o, с: bool(o.get("кольори_акценти"))),
)


def вибірка(офери, на_групу=НА_ГРУПУ, сід=СІД):
    """[(група, офер)] — по `на_групу` з кожної групи, сідом `сід`. Річ, що підійшла до кількох
    груп, лишається в ПЕРШІЙ: вибірка не має мірити ту саму річ двічі."""
    слоти, взяті, вих = {}, set(), []
    for o in офери:
        try:
            слоти[o["id"]] = ФС.слот(o)
        except Exception:                             # noqa: BLE001 — падіння слота теж вибірка
            слоти[o["id"]] = None
    for ім, _, підходить in ГРУПИ:
        пул = [o for o in офери if o["id"] not in взяті and підходить(o, слоти[o["id"]])]
        пул.sort(key=lambda o: o["id"])               # сід без порядку нічого не важить
        обрані = random.Random("%s-%s" % (сід, ім)).sample(пул, min(на_групу, len(пул)))
        взяті.update(o["id"] for o in обрані)
        вих.extend((ім, o) for o in обрані)
    return вих


def модель(промпт, ід_моделі):
    """(текст відповіді, секунд) від локальної моделі форми OpenAI; виняток — вгору, його пише
    прогін у файл речі, а не ковтає."""
    тіло = dict(model=ід_моделі, messages=[dict(role="user", content=промпт)], stream=False,
                max_tokens=int(os.environ.get("MODEL_MAX_TOKENS") or 1500))
    if os.environ.get("MODEL_TEMP"):
        тіло["temperature"] = float(os.environ["MODEL_TEMP"])
    запит = urllib.request.Request(АДРЕСА + "/chat/completions",
                                   data=json.dumps(тіло, ensure_ascii=False).encode("utf-8"),
                                   headers={"Content-Type": "application/json"})
    т0 = time.time()
    with urllib.request.urlopen(запит, timeout=3600) as в:
        дані = json.loads(в.read().decode("utf-8"))
    вибір = (дані.get("choices") or [{}])[0]
    текст = ((вибір.get("message") or {}).get("content") or "")
    return текст, round(time.time() - т0, 1)


def прогін(ід_моделі, мова="uk", куди=None, на_групу=НА_ГРУПУ, сід=СІД):
    """Вибірку — через модель у теку. Один файл на річ («── ЗАПИТ», «── ВІДПОВІДЬ»), плюс
    `прогін.json` з міркою кожного виклику. Повертає шлях теки."""
    офери, _ = ФР.читати_yml(ФК.каталог_на_диску(), показ=False)
    пари = вибірка(офери, на_групу, сід)
    куди = куди or os.path.join(ТУТ, "..", "аудит", "розбір_каталогу",
                                "%s_%s" % (ід_моделі.replace("/", "_"), мова))
    os.makedirs(куди, exist_ok=True)
    мірка = dict(модель=ід_моделі, мова=мова, url=АДРЕСА, сід=сід, на_групу=на_групу,
                 задача=КР.РОЗБІР[мова].задача, речі=[])
    for і, (група, o) in enumerate(пари, 1):
        повід = json.dumps(КР.промпт(o, мова), ensure_ascii=False, indent=1)
        try:
            відп, секунд, впало = модель(повід, ід_моделі) + (None,)
        except Exception as е:                        # noqa: BLE001 — впалий виклик названий
            відп, секунд, впало = "", 0.0, "%s: %s" % (type(е).__name__, е)
        ім = "%02d_%s_%s.txt" % (і, група, o["id"].replace("/", "_").replace("@", "_"))
        with open(os.path.join(куди, ім), "w", encoding="utf-8") as ф:
            ф.write("── ЗАПИТ\n%s\n\n── ВІДПОВІДЬ\n%s\n" % (повід, відп))
        мірка["речі"].append(dict(файл=ім, id=o["id"], група=група, секунд=секунд,
                                 знаків_запиту=len(повід), знаків_відповіді=len(відп), впало=впало))
        print("%2d/%d %-18s %-28s %5.1f с %s" % (і, len(пари), група, o["id"][:28], секунд,
                                                 впало or ""))
    with open(os.path.join(куди, "прогін.json"), "w", encoding="utf-8") as ф:
        json.dump(мірка, ф, ensure_ascii=False, indent=1)
    впали = sum(1 for р in мірка["речі"] if р["впало"])
    print("тека: %s · речей %d · впало викликів %d · лічба: проби/каталог_розбір_лічба.py"
          % (куди, len(пари), впали))
    зібрати(куди)
    return куди


# Службовий ключ `розбір.json` поруч з id оферів (id має вигляд «ж-…@крамниця» і збігтися з ним не
# може): причини кожної речі — окремо від її полів, щоб короткий запис речі з полів їх не захопив.
ПРИЧИНИ = "причини"


def зібрати(тека):
    """ЗБИРАЧ: тека прогону → `розбір.json` у тій самій теці; повертає його шлях.

    ФОРМА (з неї наряд К-3 будує короткий запис речі в пулі; ключі кодів — ті самі, що дає
    `каталог_розбір.з_відповіді`, тобто шляхи `каталог_розбір.ПОЛЯ`):
      {"<id офера>": {коди: "slot", "item_type", …, "veto": {…}; і "features": "<рядок>"},
       …,
       "причини": {"<id офера>": ["<причина>", …]}}
    Під `ПРИЧИНИ` — лише речі, що причини мають: вади форми відповіді й рядка особливостей
    (`з_відповіді`) і впалий виклик. Річ, чия відповідь не JSON або чий виклик упав, полів не має —
    під її id нічого, є лише її причини. Нічого мовчки."""
    with open(os.path.join(тека, "прогін.json"), encoding="utf-8") as ф:
        мірка = json.load(ф)
    вих, причини = {}, {}
    for р in мірка["речі"]:
        with open(os.path.join(тека, р["файл"]), encoding="utf-8") as ф:
            поля, пр = КР.з_відповіді(ф.read().split("── ВІДПОВІДЬ", 1)[-1])
        if р.get("впало"):
            пр = ["виклик упав: %s" % р["впало"]] + пр
        if поля is not None:
            вих[р["id"]] = поля
        if пр:
            причини[р["id"]] = пр
    вих[ПРИЧИНИ] = причини
    шлях = os.path.join(тека, "розбір.json")
    with open(шлях, "w", encoding="utf-8") as ф:
        json.dump(вих, ф, ensure_ascii=False, indent=1)
    рядки = sum(1 for к, п in вих.items() if к != ПРИЧИНИ and п[КР.ОСОБЛИВОСТІ] != КР.UNKNOWN)
    print("розбір: %s · речей з полями %d з %d · features не unknown %d · речей з причинами %d"
          % (шлях, len(вих) - 1, len(мірка["речі"]), рядки, len(причини)))
    return шлях


if __name__ == "__main__":
    р = argparse.ArgumentParser(description="прогін розбору каталогу на локальній мовній моделі")
    р.add_argument("--модель", default=os.environ.get("MODEL"), help="ід моделі в LM Studio")
    р.add_argument("--мова", default="uk", choices=sorted(КР.РОЗБІР), help="мова оголошення промпта")
    р.add_argument("--куди", default=None, help="тека для сирих відповідей")
    р.add_argument("--на-групу", type=int, default=НА_ГРУПУ, dest="на_групу")
    р.add_argument("--сід", type=int, default=СІД)
    р.add_argument("--зібрати", default=None, metavar="ТЕКА",
                   help="лише зібрати розбір.json з наявної теки прогону, без моделі")
    а = р.parse_args()
    if а.зібрати:
        зібрати(а.зібрати)
    elif not а.модель:
        sys.exit("без --модель (або MODEL=…) прогону не буває: модель — параметр заміру")
    else:
        прогін(а.модель, а.мова, а.куди, а.на_групу, а.сід)
