def збіги_рядка(рядок, дані, ід):
    """[(код заборони, збіг)] — УСІ збіги, а не перший на код, як `заборони_рядка`: модель при
    чистці має знати кожне слово, через яке рядок брудний. Той самий критерій, лише повніше."""
    вих = []
    for к, перший in заборони_рядка(рядок, дані, ід):
        if к == "бренд":
            вих.append((к, перший))
            continue
        т = _КАБЛУК_У_СМ.sub(" ", рядок) if к == "розмір" else рядок
        вих += [(к, м.group(0)) for м in _ЗА_РЕГІСТРОМ[к].finditer(т)] or [(к, перший)]
    return вих


def завдання_повтору(o, причини, старі, група, мова="uk"):
    """(хід, повідомлення моделі dict, стеля токенів) — повтор речі `o` за її кодами причин.

    `причини` — коди рядка `порушники.txt` («features_ban:колір», «slot_vs_group»…); `старі` —
    поля першого розбору (`розбір.json`) або None. Лише заборони й старий рядок є → `ХІД_РЯДОК`
    (оголошення `ЧИСТКА`); інакше → `ХІД_ПОВНИЙ`: промпт розбору знак у знак і примітка повтору."""
    заборони = [п.split(":", 1)[1] for п in причини if п.startswith(ПРИЧИНА_ЗАБОРОНА + ":")]
    коди_з = [КОД_ЗАБОРОНИ[к] for к in ЗАБОРОНИ if к in заборони]
    рядок = (старі or {}).get(КР.ОСОБЛИВОСТІ, КР.UNKNOWN)
    крамниця = КР.вхід(o, мова)
    if коди_з and len(заборони) == len(причини) and рядок != КР.UNKNOWN:
        к_рядок, к_прибрати, к_знайдено = _КЛЮЧІ_ЧИСТКИ[мова]
        знайдено = list(dict.fromkeys(з for _, з in збіги_рядка(рядок, крамниця, o["id"])))
        дані = dict(крамниця, **{к_рядок: рядок, к_прибрати: коди_з})
        if знайдено:
            дані[к_знайдено] = знайдено
        return ХІД_РЯДОК, ЗП.зібрати(ЧИСТКА[мова], дані), МАКС_ТОКЕНІВ_РЯДКА
    ключ, _, _, тексти = _ПРИМІТКА[мова]
    означення = _ЗАБОРОНИ_UK if мова == "uk" else _ЗАБОРОНИ_EN
    примітка = []
    if ПРИЧИНА_НЕМА in причини:
        примітка.append(тексти[ПРИЧИНА_НЕМА])
    if ПРИЧИНА_СЛОТ in причини:
        примітка.append(тексти[ПРИЧИНА_СЛОТ] % ((старі or {}).get("slot", КР.UNKNOWN),
                                                ", ".join(СЛОТ_ГРУПИ.get(група, ()))))
    if коди_з:
        примітка.append(тексти[ПРИЧИНА_ЗАБОРОНА] % "; ".join(
            "«%s» — %s" % (к, означення[к]) for к in коди_з))
    повід = КР.промпт(o, мова)
    повід[ключ] = примітка
    return ХІД_ПОВНИЙ, повід, None


def причини_з(шлях):
    """`порушники.txt` → {id: [коди причин]}."""
    with open(шлях, encoding="utf-8") as ф:
        return {р.split()[0]: р.split()[1].split(",") for р in ф if len(р.split()) > 1}


def зібрати(тека):
    """ЗБИРАЧ: тека прогону → `розбір.json` у тій самій теці; повертає його шлях.

    ФОРМА (з неї наряд К-3 будує короткий запис речі в пулі; ключі кодів — ті самі, що дає
    `каталог_розбір.з_відповіді`, тобто шляхи `каталог_розбір.ПОЛЯ`):
      {"<id офера>": {коди: "slot", "item_type", …, "veto": {…}; і "features": "<рядок>"},
       …,
       "причини": {"<id офера>": ["<причина>", …]}}
    Під `ПРИЧИНИ` — лише речі, що причини мають: вади форми відповіді й рядка особливостей
    (`з_відповіді`) і впалий виклик. Річ, чия відповідь не JSON або чий виклик упав, полів не має —
    під її id нічого, є лише її причини. Нічого мовчки."""
    with open(os.path.join(тека, "прогін.json"), encoding="utf-8") as ф:
        мірка = json.load(ф)
    вих, причини = {}, {}
    for р in мірка["речі"]:
        with open(os.path.join(тека, р["файл"]), encoding="utf-8") as ф:
            поля, пр = КР.з_відповіді(ф.read().split("── ВІДПОВІДЬ", 1)[-1])
        if р.get("впало"):
            пр = ["виклик упав: %s" % р["впало"]] + пр
        if поля is not None:
            вих[р["id"]] = поля
        if пр:
            причини[р["id"]] = пр
    вих[ПРИЧИНИ] = причини
    шлях = os.path.join(тека, "розбір.json")
    with open(шлях, "w", encoding="utf-8") as ф:
        json.dump(вих, ф, ensure_ascii=False, indent=1)
    рядки = sum(1 for к, п in вих.items() if к != ПРИЧИНИ and п[КР.ОСОБЛИВОСТІ] != КР.UNKNOWN)
    print("розбір: %s · речей з полями %d з %d · features не unknown %d · речей з причинами %d"
          % (шлях, len(вих) - 1, len(мірка["речі"]), рядки, len(причини)))
    return шлях


# Підсумки підстановки — КОДАМИ, не словами (п.12 і сканер контрактів: рядковий ключ-слово в
# індексі читається як поле фіду й вилазить «полем-сиротою»).
НЕМА_ФАЙЛА, НЕ_JSON, БЕЗ_РЯДКА = "no_file", "not_json", "no_features"
ЗАБОРОНА_ЛИШИЛАСЬ, СЛОТ_ЛИШИВСЯ, УЗЯТО = "ban_left", "slot_left", "taken"


def відповідь_повтору(тека_повтору, р, розбір):
    """(код підсумку, поля, причини) однієї речі повтору; поля й причини — лише коли `УЗЯТО`.

    ЧИСТО = те саме, що в пробі: відповідь розбирається як JSON, рядок `features` є (не unknown),
    `заборони_рядка` порожній і слот моделі не суперечить групі прогону (`слот_проти_групи`: нова
    відповідь, що й далі суперечить групі, — та сама хиба). Дані для перевірки бренду — лише ключі
    крамниці (`КЛЮЧІ_КРАМНИЦІ`), як у першому запиті: старий рядок, коди заборон і примітка
    повтору в них не йдуть. ХІД «рядок» (`ЧИСТКА`) несе лише `features`: коди — першого розбору з
    `розбір`, новий у них лише рядок; його форму лікує той самий `КР.з_відповіді`."""
    ф_шлях = os.path.join(тека_повтору, р["файл"])
    if not os.path.exists(ф_шлях):
        return НЕМА_ФАЙЛА, None, None
    with open(ф_шлях, encoding="utf-8") as ф:
        дані, відп = розділити(ф.read())
    дані = {к: в for к, в in дані.items() if к in КЛЮЧІ_КРАМНИЦІ}
    поля, пр = КР.з_відповіді(відп)
    if поля is not None and р.get("хід") == ХІД_РЯДОК:
        старі = розбір.get(р["id"])
        if старі is None:
            return БЕЗ_РЯДКА, None, None
        поля = dict(старі, **{КР.ОСОБЛИВОСТІ: поля[КР.ОСОБЛИВОСТІ]})
        пр = [п for п in (розбір.get(ПРИЧИНИ) or {}).get(р["id"], [])
              if not п.startswith(КР.ОСОБЛИВОСТІ)] + [п for п in пр if п.startswith(КР.ОСОБЛИВОСТІ)]
    if поля is None:
        return НЕ_JSON, None, None
    if поля[КР.ОСОБЛИВОСТІ] == КР.UNKNOWN:
        return БЕЗ_РЯДКА, None, None
    if заборони_рядка(поля[КР.ОСОБЛИВОСТІ], дані, р["id"]):
        return ЗАБОРОНА_ЛИШИЛАСЬ, None, None
    if слот_проти_групи(поля, р["група"]):
        return СЛОТ_ЛИШИВСЯ, None, None
    return УЗЯТО, поля, пр


def підставити(тека_повтору, тека):
    """Чисті відповіді повтору — у `розбір.json` теки прогону; брудні НЕ беруться. Повертає лічбу.

    Критерій — `відповідь_повтору`. Нечисто → під id лишається СТАРИЙ розбір: повтор може бути
    гірший за перший раз, і мовчки погіршити каталог він не має права. Причини речі переписуються
    разом з полями (вони від тієї самої відповіді), і до них додається рядок «повтор: узято» — щоб
    потім було видно, звідки взявся цей розбір."""
    with open(os.path.join(тека_повтору, "прогін.json"), encoding="utf-8") as ф:
        речі = json.load(ф)["речі"]
    шлях = os.path.join(тека, "розбір.json")
    with open(шлях, encoding="utf-8") as ф:
        розбір = json.load(ф)
    лічба = collections.Counter()
    for р in речі:
        код, поля, пр = відповідь_повтору(тека_повтору, р, розбір)
        лічба[код] += 1
        if код == УЗЯТО:
            розбір[р["id"]] = поля
            розбір[ПРИЧИНИ][р["id"]] = пр + ["повтор: узято"]
    with open(шлях, "w", encoding="utf-8") as ф:
        json.dump(розбір, ф, ensure_ascii=False, indent=1)
    print("підстановка: %s · речей повтору %d · %s"
          % (шлях, len(речі), " · ".join("%s %d" % (к, н) for к, н in sorted(лічба.items()))))
    return лічба


ПІДСУМОК_ФАЙЛ = "підсумок.txt"


def підсумок_повтору(тека_повтору, тека):
    """`підсумок.txt` теки повтору — БЕЗ підстановки (`розбір.json` не чіпає): скільки взялось би
    чистими всього, за кодом причини (річ із кількома кодами — у кожному) і за ходом, і швидкість
    стіною. Та сама лічба, що в пілоті РЗ-1 (18/40), тим самим критерієм — «до/після» способу."""
    with open(os.path.join(тека_повтору, "прогін.json"), encoding="utf-8") as ф:
        мірка = json.load(ф)
    with open(os.path.join(тека, "розбір.json"), encoding="utf-8") as ф:
        розбір = json.load(ф)
    всього, за_кодом, за_ходом = collections.Counter(), collections.defaultdict(collections.Counter), \
        collections.defaultdict(collections.Counter)
    for р in мірка["речі"]:
        код, _, _ = відповідь_повтору(тека_повтору, р, розбір)
        всього[код] += 1
        for п in set(р.get("причини") or ()):
            за_кодом[п][код == УЗЯТО] += 1
        за_ходом[р.get("хід", "?")][код == УЗЯТО] += 1
    н = len(мірка["речі"])
    дріб = lambda л: "%d/%d" % (л[True], л[True] + л[False])
    рядки = ["повтор %s, спосіб %s, модель %s, температура %s, речей %d"
             % (мірка.get("повтор_з"), мірка.get("спосіб", СПОСІБ_ТОЙ_САМИЙ), мірка.get("модель"),
                мірка.get("температура"), н),
             "чистими %d/%d (%.0f %%) · %s" % (всього[УЗЯТО], н, 100.0 * всього[УЗЯТО] / max(н, 1),
                                              " · ".join("%s %d" % кн for кн in sorted(всього.items()))),
             "за кодом причини (взято/з кодом): " + ", ".join(
                 "%s %s" % (к, дріб(л)) for к, л in sorted(за_кодом.items())),
             "за ходом: " + ", ".join("%s %s" % (к, дріб(л)) for к, л in sorted(за_ходом.items())),
             "швидкість: %.1f с/річ стіною (%d речей за %.1f хв)"
             % (мірка.get("секунд_стіною", 0) / max(н, 1), н, мірка.get("секунд_стіною", 0) / 60)]
    with open(os.path.join(тека_повтору, ПІДСУМОК_ФАЙЛ), "w", encoding="utf-8") as ф:
        ф.write("\n".join(рядки) + "\n")
    print("\n".join(рядки))
    return всього


