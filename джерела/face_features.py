"""Вимір ознак обличчя з джерелом і довірою для рангу, суду й пулу.

Кеш належить профілю. Відбиток охоплює самі риси, їхні похибки, макіяж і
протокол: копія профілю після засмаги чи фарбування не успадковує старого виміру.
"""
import hashlib
import json
import face_contrast as _KC
from колір_простір_перетворення import hx
from колір_простір_надійність import reliability, надійність_контрасту, MIN_TO_EMIT

РІВНІ_КОНТРАСТУ = (22.0, 45.0)  # T3; напрям — Candille 2012
L_ШКІРИ_ПОРОГІВ = 66.0  # T3, опора Russell / R-PC-09


def _константи():
    """Читає реєстр після завантаження фасаду colorspace, щоб не створити коло імпортів."""
    import реєстр_правил
    return реєстр_правил.C


def _походження(F):
    """Розрізняє фото, її явний ввід і відсутність виміру."""
    return "фото" if (F.get("_meta") or {}).get("from_photo") else "її слово"


def джерело_виміру(F, source=None):
    """Бере збережений протокол фото; для старого профілю — явний аргумент або типове."""
    return ((F.get("_meta") or {}).get("protocol") or source
            or ((F.get("_ознаки_обличчя") or {}).get("вимір") or {}).get("протокол")
            or "uncontrolled")


def ознаки(F, source=None):
    """Повертає один вимір рис із джерелом та довірою, спільний усім читачам."""
    source = джерело_виміру(F, source)
    вхід = {k: v for k, v in F.items() if not k.startswith("_")}
    вхід.update({k: F.get(k) for k in ("_meta", "_розподіли", "_макіяж")})
    відбиток = hashlib.sha256(json.dumps([source, вхід], sort_keys=True, ensure_ascii=False).encode()).hexdigest()
    кеш = F.get("_ознаки_обличчя") or {}
    if кеш.get("відбиток") == відбиток:
        return кеш["вимір"]
    R = dict(reliability(source))
    дж = _походження(F)
    # Явний hex не є фотографією: відтінок очей не приглушується камерою.
    довіра_тону = R["hue"] if дж == "фото" else 1.0
    риси = {k: dict(v, джерело=дж, довіра=dict(R, hue=довіра_тону))
            for k, v in вхід.items() if not k.startswith("_") and isinstance(v, dict)}
    # Старі ручні профілі могли містити лише hex. Розкладаємо його тут для всіх читачів.
    for імʼя, риса in риси.items():
        if риса.get("hex") and any(k not in риса for k in ("L", "a", "b", "C", "h")):
            import colorspace
            try:
                поля = colorspace.поля_риси(hx(риса["hex"]), "очі" if імʼя.startswith("очі") else імʼя)
            except ValueError:
                риса["помилка_кольору"] = "hex риси не читається як #rrggbb"
            else:
                риси[імʼя] = dict(поля, **риса)
    шк = риси.get("шкіра") or {}
    підтон = dict(шк, значення=шк.get("undertone"),
                  джерело=дж if шк else "типове", довіра=R["undertone"] if шк else 0.0)
    профіль = dict(F, **риси)
    к = _контраст(профіль, source)
    довіра_очей = довіра_тону if (риси.get("очі") or {}).get("b") is not None else 0.0
    вимір = dict(риси=риси, контраст=к, підтон=підтон,
                 очі=dict(риси.get("очі") or {}, джерело=дж if "очі" in риси else "типове",
                          довіра=довіра_очей),
                 бік_очей=_бік_очей(профіль, довіра_очей, дж if "очі" in риси else "типове"),
                 надійність=dict(R, contrast=к["довіра"], hue=довіра_тону), протокол=source)
    F["_ознаки_обличчя"] = dict(відбиток=відбиток, вимір=вимір)
    return вимір


def рівень_контрасту(gap):
    """Розрив світлоти волосся↔шкіри (gap) → «низький» / «середній» / «високий».

    ЄДИНЕ визначення рівня на всю систему (абзац вище): порогів було три різні —
    тут 22/45, у `profile.контраст` 20/40 і ще одні в коментарі `palette`, — а
    `palette.розвилка` ключується САМЕ на рівні, тож людина потрапляла в різні
    гілки схем залежно від шляху, яким прийшла. Самі числа — T3, некалібровані."""
    lo, hi = РІВНІ_КОНТРАСТУ
    return "низький" if gap < lo else ("середній" if gap < hi else "високий")


def _яскравість(L):
    """Відносна яскравість Y (0..1) зі світлоти L* (CIE)."""
    L = float(L)
    return ((L + 16.0) / 116.0) ** 3 if L > 8.0 else L / 903.3


def _світлота(Y):
    """L* з відносної яскравості Y (0..1), обернене до `_яскравість`."""
    Y = max(0.0, min(1.0, float(Y)))
    return 116.0 * Y ** (1.0 / 3.0) - 16.0 if Y > 0.008856 else 903.3 * Y


def _мішельсон(L_шк, L_р):
    """|Y шкіри − Y риси| / (Y шкіри + Y риси) — відносний контраст риси до шкіри."""
    a, b = _яскравість(L_шк), _яскравість(L_р)
    return abs(a - b) / (a + b) if (a + b) > 0 else 0.0


def _контраст_рис(F):
    """Відносний розкид рис у формі Russell і його L*-еквівалент на опорній шкірі."""
    шк = (F or {}).get("шкіра") or {}
    if шк.get("L") is None:
        return None
    вол = [v["L"] for k, v in F.items() if k.startswith("волосся") and isinstance(v, dict)
           and v.get("L") is not None]
    очі = (F.get("очі") or {}).get("L")
    риси = {}
    if вол:
        риси["волосся"] = _мішельсон(шк["L"], sum(вол) / len(вол))
    if очі is not None:
        риси["очі"] = _мішельсон(шк["L"], очі)
    if not риси:
        return None
    L = [float(шк["L"])] + ([sum(вол) / len(вол)] if вол else []) + ([float(очі)] if очі is not None else [])
    M = _мішельсон(max(L), min(L))       # розкид рис, не зважене середнє
    екв = None
    if float(шк["L"]) < L_ШКІРИ_ПОРОГІВ:
        Y_ref = _яскравість(L_ШКІРИ_ПОРОГІВ)
        екв = round(L_ШКІРИ_ПОРОГІВ - _світлота(Y_ref * (1.0 - M) / (1.0 + M)), 1)
    return dict(риси={k: round(v, 3) for k, v in риси.items()}, M=round(M, 3), екв_L=екв,
                опора_L=L_ШКІРИ_ПОРОГІВ)


def _контраст(F, source):
    """Обчислює фізичний контраст, відносний еквівалент, рівень і довіру за шумом зон."""
    R = reliability(source)
    шк = F.get("шкіра")
    hair = [v for k, v in F.items() if k.startswith("волосся") and not k.startswith("_")]
    if not шк or not hair:
        return dict(доступно=False, чому="нема шкіри або волосся у профілі",
                    джерело="типове", довіра=0.0, значення=None, контраст_рис=_контраст_рис(F))
    Lh = sum(h["L"] for h in hair)/len(hair)
    розкид_волосся = round((sum((h["L"] - Lh) ** 2 for h in hair) / len(hair)) ** 0.5 or 0.0, 1)
    _se_рис = [f.get("se_L") for f in [шк] + hair if isinstance(f, dict) and f.get("se_L")]
    розкид_особи = max(_se_рис) if _se_рис else None
    gap = round(abs(Lh - шк["L"]), 1)
    джерело = "ознаки обличчя: волосся ↔ шкіра"
    рис = _контраст_рис(F)
    gap_рівня = max(gap, (рис or {}).get("екв_L") or 0.0)
    if gap_рівня > gap:
        джерело = "%s; рівень — відносний контраст рис (екв. %.1f L* на шкірі L*%.0f)" % (
            джерело, gap_рівня, рис["опора_L"])
    рівень = рівень_контрасту(gap_рівня)    # ЄДИНЕ місце порогів (РІВНІ_КОНТРАСТУ)
    out = dict(доступно=True, L_шкіри=шк["L"], L_волосся=round(Lh,1),
               value_gap=round(gap,1), рівень=рівень, джерело_контрасту=джерело,
               gap_рівня=round(gap_рівня, 1), контраст_рис=рис,
               смуга_шкіри=шк.get("depth_band"),
               внутрішній_розкид_волосся=розкид_волосся,
               розкид=розкид_особи,          # похибка оцінки L* волосся, шкала se_L речей
               надійність_контрасту=надійність_контрасту(source, розкид_особи),
               пороги="межі %.0f/%.0f L* (outfit.РІВНІ_КОНТРАСТУ — єдине джерело): напрям (зсув угору) — T2 з Candille 2012 "
                      "(стиснутий контраст, r≈0.42 волосся↔шкіра); самі числа — T3" % РІВНІ_КОНТРАСТУ,
               пріор="висококонтрастний тип рідший за рівномірне припущення — "
                     "більшість людей на діагоналі світле-світле…темне-темне")
    out["макіяж"] = F.get("_макіяж")           # слід `colorspace.додати_макіяж`; None — не сказано/нюд
    out["L_обличчя"] = _KC.value_обличчя(F)     # K-CLR-04: слід; ліміт — від `L_шкіри`
    if розкид_волосся > _константи()["step_min"]:
        out["примітка"] = ("волосся саме несе контраст (мелірування/балаяж) — "
                           "образ отримує додатковий крок безкоштовно")
    if R["chroma"] >= MIN_TO_EMIT:
        очі = F.get("очі")
        out["colour_contrast"] = round(max([h.get("rel_C",0) for h in hair] +
                                           ([очі.get("rel_C",0)] if очі else [])), 2)
    else:
        out["colour_contrast"] = None
        out["утримано"] = (f"colour contrast і підтон не стверджуються: надійність хроми "
                           f"{R['chroma']} < {MIN_TO_EMIT} для джерела «{source}» (K-PC-05). "
                           "Працюємо у value-термінах; про метали й білі — питати людину")
    out.update(значення=out["value_gap"], джерело=_походження(F),
               довіра=out["надійність_контрасту"]["надійність"])
    return out


def _бік_очей(F, довіра, джерело):
    """Тіло `бік_b_проти_людини` — без точки зламу руки 2."""
    межа_т, межа_х = _константи()["b_нейтралі"]
    очі = (F or {}).get("очі") or {}
    шк = (F or {}).get("шкіра") or {}
    ita = шк.get("ITA"); ita_смуга = шк.get("ITA_смуга")
    b = очі.get("b"); b_чому = очі.get("помилка_кольору")
    база = dict(довіра=довіра, джерело_виміру=джерело, правило="R-COL-16", риса="очі", тір="T2", сила="hint",
                межі=dict(теплий_від=межа_т, холодний_до=межа_х),
                ITA_шкіри=ita, ITA_смуга=ita_смуга,
                ITA_не_ключ="тема-2 §6.1 / K-COND-02: меланін шкіри вибору не рухає, очі рухають")
    if b is None:
        return dict(база, вхід=False, бік=0, b_очей=None,
                    чому=b_чому or "у профілі нема кольору очей — бік b* не читається")
    b = float(b)
    if b > межа_т: бік = 1
    elif b < межа_х: бік = -1
    else: бік = 0
    if бік == 0:
        return dict(база, вхід=False, бік=0, b_очей=round(b, 1),
                    чому="b* очей %.1f в ахроматичній смузі [%.1f..%.1f] — бік не стверджується"
                         % (b, межа_х, межа_т))
    межа = межа_т if бік > 0 else межа_х
    сила = min(1.0, abs(b - межа) / float(_константи()["b_очей_повна"]))
    return dict(база, вхід=True, бік=бік, сила_боку=сила, b_очей=round(b, 1),
                джерело="b* райдужки (Perrett 2023: вибір іде за очима)",
                чому="b* очей %.1f — %s бік жовто-синьої осі; речі біля обличчя з того самого "
                     "боку читаються рівніше (T2 · hint, порядок, не вікно)"
                     % (b, "теплий" if бік > 0 else "холодний"))



