def сім_я_схеми(lab, сім_ї):
    """Роль схеми, чию сім'ю несе річ, або None.

    `сім_ї` — `специфікація(...)["сім_ї_схеми"]`: [{роль, дуга}] для схеми з
    `поверхні="великі"`. Річ несе сім'ю, коли її C* не нижча за `МЕЖА_СІМ_Ї` і тон лежить
    у дузі (з обходом через 0°). Нема виміру кольору — None: невимір не зараховується
    ні за колір, ні за провал (та сама політика, що в `palettes.обіцянка_схеми`)."""
    if not lab or len(lab) < 3:
        return None
    _L, C, h = cs.lch(lab)
    if C < МЕЖА_СІМ_Ї:
        return None
    for с in сім_ї or ():
        lo, hi = float(с["дуга"][0]), float(с["дуга"][1])
        if (lo <= h <= hi) if lo <= hi else (h >= lo or h <= hi):
            return с["роль"]
    return None

# K-COL-03 «Схеми за спаданням надійності»: (1) нейтральна база + акцент,
# (2) тональна/монохромна, (3) аналогова, (4) приглушена комплементарна,
# (5) тріада — advanced. Ранг береться з ПОРЯДКУ `СХЕМИ`, а не пишеться другим
# списком: два списки розійшлись би тихо.
def _дуга(h, пів):
    """Дуга тону навколо `h` ± `пів` градусів, як пара (від, до) по колу 0–360."""
    return (round((h - пів) % 360, 1), round((h + пів) % 360, 1))

