def пропорція(схема, рівень, intent="conventional"):
    """Під-розвилка ЧАСТОК для гілки схеми: які стратегії пропорції законні тут.
    Це МЕХАНІЗМ дивергенції «малий акцент vs збалансовано», яку розвилка схем лише
    називала й не могла виразити. Окремі випадки:
      тональна — 60-30-10 йде по КРОКАХ СВІТЛОТИ, не по тонах (монохром);
      нейтрали+акцент — означенням градуйована (нейтраль домінує, акцент малий);
      тріада — один тон домінує, два інші акценти, інакше три конкурентні фокуси."""
    conv = _РЕЄСТР.стриманий_намір(intent)   # K-PER-00: comfort_first / context_optimal — теж конвенція
    if схема == "тональна":
        стратегії, нота = ["градуйована"], ("монохром: частки — це розподіл ПЛОЩ по кроках "
            "світлоти, не по тонах")
    elif схема == "нейтрали+акцент":
        стратегії, нота = ["градуйована"], "означенням: нейтраль тримає поле, акцент малий"
    elif схема == "тріада":
        стратегії, нота = ["градуйована"], ("один тон домінує, два — акценти (інакше три "
            "конкурентні фокуси)")
    else:  # аналогова, приглушена_комплементарна — тут живе розвилка часток
        стратегії = ["градуйована"]
        if not (рівень == "низький" and conv):     # колор-блок незаконний лише на низькому+conv
            стратегії.append("колор-блок")
        нота = ("градуйована (малий акцент) АБО колор-блок (рівніші поля) — обидві законні; "
                "саме тут дивергенція «скільки другого кольору», яку схема-розвилка називала")
    return dict(стратегії=[dict(назва=s, **ПРОПОРЦІЯ[s]) for s in стратегії],
                за_замовчуванням="градуйована", нота=нота,
                зв_язок_контрасту="домінанта на ідеальному value (≈L волосся); акцент несе "
                                  "контраст; видима вага = площа×near",
                провенанс="ЯДРО конвергентне (нерівні частки, акцент найменший) — сильніше за "
                          "T3; ЧИСЛА (60/30/10) запозичені з інтердизайну — орієнтир, не гейт")

НОСІЇ_АКЦЕНТУ = ("сумка", "взуття", "шарф", "прикраси", "пояс", "головний_убір")

def розподіл_ролей(слоти, S, фокус=None):
    """ЗНАЙДЕНО ЗАМКНЕНИМ ЦИКЛОМ: схема оголошувала відлуння, а специфікація давала
    рівно один акцентний слот — і outfit.py блокував такий образ як «сирота-акцент».
    Породжувальний шар суперечив перевіряльному, а примітка «потрібне відлуння»
    цього не рятувала: композитор виконав би специфікацію буквально й отримав блокер.
    Тепер акцент розкладається на двох носіїв; якщо носій один — специфікація вимагає
    оголошеної фокусної зони, інакше вона невиконанна і про це сказано прямо."""
    ролі = {s: ДЕФОЛТ_РОЛЕЙ.get(s, "акцент") for s in слоти}
    if not S["відлуння"]: return ролі
    носії = [s for s in слоти if s in НОСІЇ_АКЦЕНТУ]
    for s in носії[:2]: ролі[s] = "акцент"
    return ролі

# ── ВІДПОВІДНІСТЬ ДВОХ СЛОВНИКІВ ВІДНОШЕНЬ — ВИМІРЯНА, НЕ ОГОЛОШЕНА ────────────
# `colorspace.RELATIONS` і `СХЕМИ[...]["тон"]` — два словники про одне (яке кутове
# відношення тону речі до якоря). Мапінг між ними міг би бути конвенцією; він нею
# не є: `звірити_відношення()` нижче міряє ЗСУВИ обох і показує, що вони збігаються
# точно (0/120/180), а розходяться лише ПІВ-ШИРИНИ — і один зсув (аналогова, акцент
# +55°) у RELATIONS не покритий узагалі. Розходження названо, а не згладжено.
ВІДНОШЕННЯ_СХЕМИ = {
 "нейтрали+акцент": "analogous",          # єдина кольорова роль — акцент, дуга ±20 навколо якоря
 "тональна": "tonal",                     # збіг ТОЧНИЙ, разом із пів-шириною (0,12)
 "аналогова": "analogous",
 "приглушена_комплементарна": "complementary",
 "тріада": "triadic",
}


def звірити_відношення():
    """Чи мапінг СХЕМИ→RELATIONS є виміром, а не конвенцією. Повертає розходження
    поіменно: {схема: [(роль, зсув_схеми, покрито_RELATIONS?)]}. Порожньо = збіг."""
    out = {}
    for назва, rel in ВІДНОШЕННЯ_СХЕМИ.items():
        off, w = cs.RELATIONS[rel]
        дозволені = {0.0, float(off), float((-off) % 360)}
        for роль, дуга in СХЕМИ[назва]["тон"](0.0).items():
            if дуга == "нейтраль": continue
            lo, hi = дуга
            зсув = round(((lo + ((hi - lo) % 360) / 2) % 360), 1)
            пів = round(((hi - lo) % 360) / 2, 1)
            покрито = any(abs(((зсув - d + 180) % 360) - 180) <= w for d in дозволені)
            if not покрито:
                out.setdefault(назва, []).append(
                    dict(роль=роль, зсув_схеми=зсув, пів_схеми=пів,
                         відношення=rel, зсув_RELATIONS=off, пів_RELATIONS=w))
    return out
