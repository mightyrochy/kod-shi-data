# ЩО БУЛО. `palettes.обіцянка_схеми` (K-COL-03) мовчала, щойно БУДЬ-ЯКА річ образу була
# кольоровою: рожева сумка «виконувала» тріаду. K-COMP-03 (`колір_хрома.сім_ї_образу`) —
# стеля (понад три сім'ї), не вимога; K-PAL-18 питав лише, чи акцентний слот несе хрому.
# Тобто ніхто не питав, чи сім'ї схеми стоять на ВЕЛИКИХ речах і в яких площах, а запис
# тріади сам казав «ручний баланс площ».
# ЩО ТЕПЕР. Площі сімей рахує код (`площі_схеми`), суд вимагає сім'ї схеми на великих
# речах (`обіцянка_великих`: знахідка K-COL-03 з регістром і `сила_нп`), а жінка читає
# одне речення її словами (`рядок_великих`). Коли під сім'ю в доборі великих речей нема,
# це кажеться «браком асортименту» з тим, чого бракує, а не мовчанням.
# ЧОМУ ТУТ, А НЕ В `palettes`. Означення «котру сім'ю несе річ» (`сім_я_схеми`) одне на
# добір (`міст_пакет`) і суд — і стоїть поруч із самими схемами; `palettes.py` підійшов
# до стелі 1 500 рядків (СТАНДАРТ_КОДУ п.16), тож його `обіцянка_схеми` й
# `рядок_схеми_жінці` лише передають сюди схему великих поверхонь.

# «Приблизно порівну» словами власниці 22.09 — числом: найменша сім'я займає щонайменше
# половину площі найбільшої. T3, конвенція, а не виміряне сприйняття; назване тут, щоб
# його можна було перекалібрувати одним рядком.
БАЛАНС_ПЛОЩ = 0.5
# Краї ВЕЛИКОЇ речі, коли їх не дали ні річ, ні слово (`composer._у_річ` ставить їх для
# верху, низу, сукні й комплекту; верхньому шару — ні). Верхній шар без краю — жакет:
# найкоротший законний шар, тобто площа його не завищена.
_КРАЇ_СЛОТА = {"верх": ("плечі", "стегна"), "низ": ("талія", "коліно"),
               "сукня": ("плечі", "коліно"), "комплект": ("плечі", "коліно"),
               "верхній_шар": ("плечі", "стегна")}
_СИЛА_НП_К03 = {"hard": 0.95, "strong": 0.75, "default": 0.5, "soft": 0.35, "hint": 0.2}


def _lab_речі(r, за_ід):
    """Lab речі з каталогу за id (рядок пулу `lab` не несе) або з її hex; None — невимір.

    Нечитний hex — та сама гілка, що й річ без hex: `cs.hx` кидає лише ValueError на
    рядку не у формі «#rrggbb», і політика «невимір — не провал» каже рахувати таку
    річ невиміряною, а не нейтральною."""
    повна = (за_ід or {}).get(r.get("id")) or r
    lab = повна.get("lab")
    if not lab and повна.get("hex"):
        try:
            lab = cs.hx(повна["hex"])
        except ValueError:
            lab = None
    return lab if lab and len(lab) >= 3 else None


def площі_схеми(речі, сім_ї, тіло=None, за_ід=None):
    """Скільки площі образу несе кожна сім'я схеми — на ВЕЛИКИХ речах, кодом.

    Вихід: dict(сім_ї={роль: dict(площа, частка, слоти, речі)}, нейтральні=[(слот, id)],
    аксесуари={роль: [(слот, id)]}, невиміряні=<великих речей без кольору>,
    великі=[(слот, id)] — усі великі речі образу, виміряні чи ні (план ремонту
    рахує по них, які шари ще вільні),
    баланс=<найменша частка / найбільша серед присутніх сімей або None>,
    дефолтних=<скільки країв узято з дефолту слота>, джерело=<рядок>).
    Площа — `areas.площа_виробу` на профілі ЦЬОГО тіла між краями речі (річ, слово чи
    дефолт слота — `composer._у_річ` їх уже поставив; верхній шар без краю бере жакет із
    `_КРАЇ_СЛОТА`), без перекриття шарами: взірець власниці рахує жакет, сорочку й
    спідницю як три приблизно рівні поля. Без профілю тіла площі нема — частки None, і
    це сказано в `джерело`, а не нулем."""
    import areas as _AR
    проф = (тіло or {}).get("профіль")
    H = (тіло or {}).get("висоти") or {}
    вих = {с["роль"]: dict(площа=0.0, частка=None, слоти=[], речі=[]) for с in сім_ї}
    нейтральні, аксесуари, невиміряні, дефолтних, відмови = [], {}, 0, 0, []
    великі_слоти = []
    for r in речі or ():
        сл, lab = r.get("слот"), _lab_речі(r, за_ід)
        р = сім_я_схеми(lab, сім_ї)
        if сл not in ВЕЛИКІ_ПОВЕРХНІ:
            if р:
                аксесуари.setdefault(р, []).append((сл, r.get("id")))
            continue
        великі_слоти.append((сл, r.get("id")))
        if lab is None:
            невиміряні += 1
            continue
        if not р:
            нейтральні.append((сл, r.get("id")))
            continue
        вих[р]["слоти"].append(сл)
        вих[р]["речі"].append(r.get("id"))
        if not проф:
            continue
        в, н = r.get("верх_см"), r.get("низ_см")
        if в is None or н is None or r.get("край_джерело") == "дефолт слота":
            дефолтних += 1
        if в is None or н is None:
            в, н = (H.get(x) for x in _КРАЇ_СЛОТА[сл])
        try:
            вих[р]["площа"] += _AR.площа_виробу(проф, в, н)
        except (TypeError, ValueError) as е:     # край поза профілем тіла — названо нижче
            відмови.append("%s: %s" % (r.get("id"), е))
    разом = sum(v["площа"] for v in вих.values())
    for v in вих.values():
        if разом > 0 and v["слоти"]:
            v["частка"] = round(v["площа"] / разом, 3)
    частки = [v["частка"] for v in вих.values() if v["частка"]]
    баланс = round(min(частки) / max(частки), 3) if len(частки) >= 2 else None
    джерело = ("нема профілю тіла: площі не пораховано" if not проф else
               "геометрія речей на цьому тілі, без перекриття шарами; дефолтних країв %d%s"
               % (дефолтних, ("; відмовила геометрія: " + "; ".join(відмови)) if відмови else ""))
    return dict(сім_ї=вих, нейтральні=нейтральні, аксесуари=аксесуари, невиміряні=невиміряні,
                баланс=баланс, дефолтних=дефолтних, джерело=джерело, великі=великі_слоти)


# ШАРИ, ЯКІ МОЖНА ДОДАТИ ДО ОБРАЗУ, — ПО ОДНОМУ КОЛЬОРУ НА ШАР (рядок 145). ДО: «додай» не
# рахувало шарів, і образ-сукня при +18 °C (верхній шар знято погодою) діставав «оливковий
# і рожевий можна додати жакетом чи кардиганом» — два кольори одним жакетом. Шар «верх» —
# жакет чи кардиган другим шаром: вільний, поки верхів в образі менше двох. Верхній шар —
# коли його в образі нема; чи його дає погода, каже добір (`у_пулі`): при +18 його там нема.
_ШАРИ = (("верх", "жакетом чи кардиганом"), ("верхній_шар", "верхнім шаром"))
# Велика річ, що сама закриває і верх, і низ: третій колір тут потребує окремих верху й
# низу замість неї.
_ЦІЛЬНІ = ("сукня", "комплект")
_ЦІЛЬНІ_РОД = {"сукня": "сукні", "комплект": "комплекту"}


def план_ремонту(пл, сім_ї, у_пулі):
    """Що зробити з кожною сім'єю схеми, якої бракує на великих речах образу.

    [(роль, дія, слот, id)]: «заміни» — велику річ образу (нейтральну або зайвого носія
    сім'ї, що стоїть на великих речах двічі, — одного з них), у чий слот добір має цю
    сім'ю; «додай» — шаром (`слот` — який шар: «верх» чи «верхній_шар»), ОДИН шар — ОДНА
    сім'я, і лише шар, вільний у цьому образі й наявний для сім'ї в доборі; «перебудуй» —
    шарів не вистачило, а образ стоїть на сукні чи комплекті: сім'ї потрібні окремі верх
    і низ замість цієї речі (`слот`, `id` — сама річ); «деінде» — сім'я в доборі є лише в
    слотах, яких цей образ не має і які не додаси шаром; «брак» — великих речей цієї
    сім'ї в доборі нема. `у_пулі` — {роль: {слот: скільки}}. Одна річ і один шар
    віддаються лише під одну сім'ю."""
    # ЇЇ РІЧ НЕ МІНЯЄТЬСЯ (рядок 176): «не ця» на її речі не стоїть (рядок 152), і міняти її
    # вона не просила — тож її річ (id «її-…») не кандидат ні на «заміни», ні на «перебудуй»;
    # сім'ї тоді лишаються шар або «деінде»
    _її = lambda і: str(і or "").startswith("її-")
    вільні = [(сл, і, None) for сл, і in пл["нейтральні"] if not _її(і)]
    квота = {}
    for р, v in пл["сім_ї"].items():
        if len(v["речі"]) > 1:
            квота[р] = len(v["речі"]) - 1
            вільні += [(сл, і, р) for сл, і in zip(v["слоти"], v["речі"]) if not _її(і)]
    план, решта = [], []
    for с in сім_ї:
        р = с["роль"]
        if пл["сім_ї"][р]["слоти"]:
            continue
        де = (у_пулі or {}).get(р) or {}
        з = next((x for x in вільні if x[0] in де and (x[2] is None or квота.get(x[2], 0) > 0)), None)
        if з:
            вільні.remove(з)
            if з[2] is not None:
                квота[з[2]] -= 1
            план.append((р, "заміни", з[0], з[1]))
        elif not де:
            план.append((р, "брак", None, None))
        else:
            решта.append(р)
    слоти = [сл for сл, _ in (пл.get("великі") or ())]
    шари = [сл for сл, _ in _ШАРИ
            if (слоти.count("верх") < 2 if сл == "верх" else сл not in слоти)]
    # сім'я з меншим вибором шарів бере свій першою — інакше жакет міг би піти сім'ї,
    # яка мала ще й верхній шар, а друга лишилась би ні з чим
    for р in sorted(решта, key=lambda р: sum(1 for ш in шари if ш in у_пулі[р])):
        ш = next((ш for ш in шари if ш in у_пулі[р]), None)
        if ш:
            шари.remove(ш)
            план.append((р, "додай", ш, None))
            continue
        ціла = next(((сл, і) for сл, і in (пл.get("великі") or ()) if сл in _ЦІЛЬНІ and not _її(і)), None)
        if ціла and set(у_пулі[р]) & {"верх", "низ"}:
            план.append((р, "перебудуй", ціла[0], ціла[1]))
        else:
            план.append((р, "деінде", None, None))
    порядок = [с["роль"] for с in сім_ї]
    return sorted(план, key=lambda x: порядок.index(x[0]))


def _великі_у_пулі(сім_я, кандидати, за_ід):
    """{слот: скільки речей несуть цю сім'ю} серед ВЕЛИКИХ слотів пулу."""
    вих = {}
    for сл in ВЕЛИКІ_ПОВЕРХНІ:
        n = sum(1 for x in ((кандидати or {}).get(сл) or ())
                if сім_я_схеми(_lab_речі(x, за_ід), [сім_я]))
        if n:
            вих[сл] = n
    return вих


def _великі_у_каталозі(сім_я, за_ід):
    """Скільки ВЕЛИКИХ речей усього каталогу (`за_ід` — id → запис) несуть цю сім'ю."""
    return sum(1 for x in (за_ід or {}).values()
               if x.get("слот") in ВЕЛИКІ_ПОВЕРХНІ and сім_я_схеми(x.get("lab"), [сім_я]))


def обіцянка_великих(речі, спец_слоти, за_ід=None, кандидати=None, тіло=None):
    """[знахідки] K-COL-03 для схеми великих поверхонь — чи її сім'ї стоять на великих
    речах образу, і чи приблизно порівну.

    Дві гілки. (1) Великі речі несуть менше сімей, ніж обіцяє схема (тріада — три,
    приглушена комплементарна — дві): знахідка називає, яких бракує, чи колір лише на
    аксесуарах, і чи сім'я була в доборі великих речей — інакше «брак асортименту»
    з числом у каталозі. (2) Сім'ї всі, але найменша займає менше `БАЛАНС_ПЛОЩ` від
    найбільшої. Сила — корпусна K-COL-03 (`реєстр_правил.сила_за_корпусом`), регістр
    звідти ж: невиконана схема — те, що жінці кажуть, а не вето. Мовчить, коли сімей
    схеми нема з чого взяти (тон не заякорено) або жодної великої речі не виміряно."""
    сім_ї = (спец_слоти or {}).get("_сім_ї") or []
