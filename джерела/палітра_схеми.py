def зсув_мисматчу(gap):
    """Свідомо протилежний контраст для драбини світлоти.

    Повертає {власний, підставлений, рівень_власний, рівень_образу, чому} — без
    базової схеми: її обирає той, хто має розвилку (`палітра_специфікація`).

    ЗВІДКИ ЧИСЛО, І ЧОМУ НЕ ЗІ СТЕЛІ. Єдина шкала рівнів контрасту в системі —
    `outfit.РІВНІ_КОНТРАСТУ` (22 / 45 L*): на ній стоїть `рівень_контрасту`, нею
    ж ключується `частки_блоків` і вся розвилка. Підставлене значення — ДЗЕРКАЛО
    власного відносно середини цієї шкали: низькоконтрастна дістає
    висококонтрастну драбину, висококонтрастна — низькоконтрастну, і крок від
    середини рівно такий, яким був крок до неї. Жодного нового числа тут не
    заведено — обидві межі читаються, а не копіюються.

    ДВА ЗАТИСКИ, обидва з наявних шкал:
      · відхил не менший за ОДИН розрізнюваний крок світлоти (`C["step_min"]`,
        той самий, що тримає K-COL-01). Без нього людина рівно посередині шкали
        дістала б «мисматч», який не змінює нічого, — мовчазну обіцянку;
      · саме́ підставлене значення не нижче одного кроку: від нього рахується
        вікно біля обличчя (`колір_образу.цільове_вікно`), і контраст, менший за
        розрізнюваний крок, означав би образ, який на світлоті не читається.

    ДЕ ЛАМАЄТЬСЯ: дзеркало — конвенція (T3), як і самі пороги 22/45. Виміряного
    числа, з якого «протилежний контраст» починається, ніхто не давав; що тут
    виміряно — наслідок на каталозі (`проби/mysmatch_122.py`: пул кожного слота
    непорожній, розмах світлоти пулу й склад вибірки видимо інші).
    """
    lo, hi = O.РІВНІ_КОНТРАСТУ
    крок = float(_РЕЄСТР.C["step_min"])
    центр = (float(lo) + float(hi)) / 2.0
    власний = float(gap or 0.0)
    м = 2.0 * центр - власний
    if abs(м - власний) < крок:          # середина шкали: дзеркало нічого не міняє
        м = власний + крок * (1.0 if власний <= центр else -1.0)
    м = max(крок, м)
    рв, ро = O.рівень_контрасту(власний), O.рівень_контрасту(м)
    return dict(гілка=МИСМАТЧ, власний=round(власний, 1), підставлений=round(м, 1),
                рівень_власний=рв, рівень_образу=ро,
                чому=("контраст образу свідомо НЕ під контраст особи: власний %.1f L* "
                      "(%s) дзеркалиться в %.1f L* (%s) навколо середини шкали рівнів "
                      "%.0f/%.0f" % (власний, рв, м, ро, lo, hi)))

