# ── ЛЮДИНА — ЗОНА, НЕ ВІДРО (28.08.2026) ────────────────────────────────────
# ФЕЙЛ-КЕЙС, виміряний свіпом волосся на фіксованій шкірі: gap 17.5 → «тональна: ядро»,
# 22.6 → «звичайна», 47.8 → «на_межі». Два стрибки по 0.4 ваги на порогах 22/45 L*, між
# ними нічого; пороги — T3 (некалібровані), тобто категорія, від якої залежить перша
# гілка палітри, різалась числом, точність якого ніхто не міряв.
# after: частка належності до кожного блоку — неперервна функція value-gap. Перехід
# лінійний, шириною в ОДИН розрізнюваний крок світлоти (реєстр_правил.C["step_min"], T2,
# K-COL-01): поріг T3 не може бути відомий точніше за крок, який око взагалі відрізняє,
# тож у смузі ±півкроку від порога людина належить обом сусіднім блокам у пропорції.
# Ваги гілок = сума ваг у блоках, зважена частками. Далеко від порогів це ТІ САМІ блоки
# корпусу (гейт §34 звіряє), тобто практика не переписана — прибрано лише стрибок.
# Шкала переведення порядкової ваги в число — НЕ вимір (як hypergraph.ВАГА_СИЛИ); вона
# лише зберігає порядок «ядро > звичайна > на_межі» і дає чим інтерполювати.
_ВАГА_НП = {"ядро": 1.0, "звичайна": 0.6, "на_межі": 0.3}

def частки_блоків(gap, ширина=None):
    """{низький, середній, високий} — частки належності, сума 1, неперервні за gap."""
    if gap is None: return None
    lo, hi = O.РІВНІ_КОНТРАСТУ
    w = float(ширина if ширина is not None else _РЕЄСТР.C["step_min"]) / 2.0
    w = min(w, (hi - lo) / 2.0)          # смуги двох порогів не перекриваються
    рампа = lambda x, п: min(1.0, max(0.0, (x - (п - w)) / (2.0 * w))) if w > 0 else float(x >= п)
    a, b = рампа(gap, lo), рампа(gap, hi)
    return dict(низький=round(1.0 - a, 3), середній=round(a - b, 3), високий=round(b, 3))

def _вага_словами(нп):
    """Неперервна вага гілки → порядкове слово корпусу (ядро / звичайна / на_межі);
    пороги — та сама шкала, що й `_ВАГА_НП`, лише навпаки."""
    return "ядро" if нп >= 0.8 else "звичайна" if нп >= 0.45 else "на_межі"

