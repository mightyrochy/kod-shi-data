# ЩО БУЛО. `palettes.рядок_схеми_жінці` для тріади писав «його мали нести сумка або
# взуття — а цей образ вийшов увесь нейтральний», тобто обіцяв жінці те, від чого
# власниця відмовилась: тріада — не сумка. І мовчав, щойно хоч одна річ образу була
# кольоровою (рожева сумка на нейтральному образі «виконувала» тріаду).
# ЩО ТЕПЕР. Рядок каже, які кольори схема тримає на великих речах, які з них образ
# справді несе, де колір лише відлунює, і що робити: «не ця» на нейтральній великій
# речі, коли потрібна річ у доборі є; «брак асортименту» — коли її нема. Без кодів,
# id і чисел (`ВИМОГИ_ОПИСУ`), без слова «ші» (CLAUDE.md п.7), без замків (п.9).
_ВЕЛИКІ_НА = {"верх": "верху", "низ": "низу", "сукня": "сукні", "комплект": "комплекті",
              "верхній_шар": "верхньому шарі"}


def слово_сім_ї(с, основа=None):
    """Назва сім'ї схеми словом крамниці.

    Слово основи, яке спека вже поклала в сім'ю (`слово`), або основа жінки
    (`вибір_кольору`: `база`, `база_hex`), коли її тон лежить у дузі сім'ї, — вона сама
    так назвала цей колір. Інакше — слово лексикону для зразка сім'ї (`зразок`,
    `специфікація`): найтісніше вікно `palettes._назва`, тим самим правилом, яким
    підписано основи на екрані палітри."""
    import palettes as _ПЛ, verify as _V
    if с.get("слово"):
        return с["слово"]
    о = основа or {}
    if о.get("база") and о.get("база_hex") and сім_я_схеми(cs.hx(о["база_hex"]), [с]):
        return str(о["база"]).split("·")[0]
    if с.get("зразок"):
        return _ПЛ._назва(cs.hx(с["зразок"]), виключити=_V.МЕТАЛИ)[0]
    return str(с["роль"])


# СЛОВО СІМ'Ї — СЛОВО ЇЇ РЕЧЕЙ (рядок 145). Членство в сім'ї — дуга тону й C* ≥ 12 за
# БУДЬ-ЯКОЇ світлоти (`сім_я_схеми`): блакитна сорочка взірця власниці — законний член
# тріади поруч із «петролем». ДО сім'ю називало слово ОДНОГО відтінку з фіксованою
# світлотою (лексикон по зразку), і жінка читала «великі речі несуть петроль» над
# небесно-блакитною сукнею (ж-01466@vilni.store, «блакитний»). Слово лексикону тут
# неправдиве за побудовою: сім'я ширша за будь-який один відтінок. Тепер сім'ю
# називають її речі — слово крамниці (`колір_назва`), тим правилом, яким власниця
# визначила вікно слова (п.9: «якщо магазини називають його бежевим, значить він бежевий»).
def слово_речі(r, за_ід=None):
    """Колір речі словом крамниці (`колір_назва`) — або None, коли крамниця не назвала."""
    повна = (за_ід or {}).get(r.get("id")) if isinstance(r, dict) else (за_ід or {}).get(r)
    повна = повна or (r if isinstance(r, dict) else {})
    н = str(повна.get("колір_назва") or "").strip().lower()
    return н or None


def слова_у_речах(речі, сім_я, за_ід=None, n=2):
    """Найчастіші слова крамниці серед речей, що несуть `сім_я` (не більше `n`).

    `речі` — записи або id; колір береться з каталогу (`за_ід`), бо рядки пулу `lab` не
    несуть. Порядок — частота, при рівній — перша зустріч."""
    лік = {}
    for r in речі or ():
        if сім_я_схеми(_lab_речі(r if isinstance(r, dict) else {"id": r}, за_ід), [сім_я]):
            с = слово_речі(r, за_ід)
            if с:
                лік[с] = лік.get(с, 0) + 1
    return [с for с, _ in sorted(лік.items(), key=lambda x: -x[1])][:n]


def слова_сімей(сім_ї, пл, за_ід=None, основа=None, у_доборі=None):
    """{роль: слово} — одне слово на сім'ю схеми, те саме в усьому рядку.

    Черга: (1) річ ЦЬОГО образу, що несе сім'ю, — її слово крамниці (що жінка бачить на
    фото й у підписі); (2) основа жінки, коли сім'я — її (вона сама так назвала колір);
    (3) найчастіше слово тих речей добору, що несуть сім'ю (`у_доборі` — {роль: [слова]},
    `міст_пакет` кладе їх у `_схема_великі`; коли в доборі їх нема — слова каталогу);
    (4) лексикон по зразку (`слово_сім_ї`) — лише коли речей сім'ї нема ніде."""
    вих = {}
    for с in сім_ї:
        р = с["роль"]
        носії = [x for x in (слово_речі(і, за_ід) for і in пл["сім_ї"][р]["речі"]) if x]
        о = основа or {}
        if носії:
            вих[р] = носії[0]
        elif о.get("база") and о.get("база_hex") and сім_я_схеми(cs.hx(о["база_hex"]), [с]):
            вих[р] = str(о["база"]).split("·")[0]
        elif (у_доборі or {}).get(р):
            вих[р] = у_доборі[р][0]
        else:
            вих[р] = слово_сім_ї(с, основа)
    return вих


def _з_великої(т):
    """Перша літера речення — велика, решта як є (`str.capitalize` зменшила б решту)."""
    return т[:1].upper() + т[1:]


def _разом(слова):
    """«а, б і в» — перелік ТИХ, що є разом (на противагу `palettes._перелік` з «або»)."""
    сп = [x for x in слова if x]
    return "" if not сп else сп[0] if len(сп) == 1 else "%s і %s" % (", ".join(сп[:-1]), сп[-1])


def рядок_великих(речі, спец_слоти, за_ід=None, великі=None, обрана=True, основа=None, тіло=None):
    """Один рядок жінці про схему великих поверхонь — або None, коли казати нема чого.

    `великі` — `пак["_схема_великі"]` (`міст_пакет`): де в доборі лежать великі речі
    кожної сім'ї і, коли їх нема, скільки їх у каталозі. `основа` — `вибір_кольору`
    (слово основи для її сім'ї), `тіло` — для площ (без нього рядок про баланс мовчить).
    Мовчить, коли сім'ї схеми на великих речах усі й площі близькі, коли жодної
    великої речі не виміряно, і коли тон схеми не заякорено."""
    сім_ї = (спец_слоти or {}).get("_сім_ї") or []
    схема = str((спец_слоти or {}).get("_схема") or "").replace("_", " ")
    if not сім_ї or not схема:
        return None
    пл = площі_схеми(речі, сім_ї, тіло, за_ід)
    дані = {с.get("роль"): с for с in ((великі or {}).get("сім_ї") or [])}
    слово = слова_сімей(сім_ї, пл, за_ід, основа, {р: д.get("слова") for р, д in дані.items()})
    є = [с["роль"] for с in сім_ї if пл["сім_ї"][с["роль"]]["слоти"]]
    if not (є or пл["нейтральні"]):
        return None
    зачин = ("Схема «%s»" % схема) if обрана else ("Схема «%s», яку взяв код," % схема)
    суть = ("%s — це %s на великих речах приблизно порівну: %s."
            % (зачин, "три кольори" if len(сім_ї) == 3 else "дві сторони пари",
               _разом([слово[с["роль"]] for с in сім_ї])))
    бракує = [с["роль"] for с in сім_ї if с["роль"] not in є]
    if not бракує:
        if пл["баланс"] is None or пл["баланс"] >= БАЛАНС_ПЛОЩ:
            return None
