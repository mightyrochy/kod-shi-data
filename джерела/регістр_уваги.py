# ── ДЕ РІЧ ВЕДЕ ПОГЛЯД (ФОКУС-3, рядок 1520) ────────────────────────────────────────────
# ЩО БУЛО. «Приховати» судило КОЖНУ річ образу: на ж4 р1 («приховати живіт») знахідка «річ
# помітна собою» стояла на малахітових сережках, ремонт замінив їх перлами — і образ став
# суто чорним. Сережки біля обличчя ведуть погляд угору, геть від живота: корпус каже
# поставити те, що вирізняється, туди, де має бути фокус (K-COL-08 «put advancing properties
# where the focus should be»; K-CRA-02 — фокус «where the eye should go on this body»), а
# мета «приховати» — напрям уваги ВІД зони (тема-6 §1.6). ЩО ТЕПЕР. Коли вона назвала зону
# (`мета_зони` паспорта, код `goal_zones`), знахідка лишається лише на речах, що стоять у зоні
# чи ведуть до неї погляд (слоти нижче), і на речах, що цю зону відкривають
# (`outfit.зони_речі`); річ поза зоною працює на мету. Без зони — як доти, увесь образ.
# Слоти — геометрія тіла, не поріг: що лежить на зоні чи замикає на ній лінію (пояс, сумка
