def слоти_ремонту(образи):
    """Слоти, які просить R-CHEV-08, — для вітрини ремонту (`повнота_образу._вітрина_ремонту`).

    ЧОМУ ЦЕ ОКРЕМИЙ КАНАЛ, А НЕ «САМО ДОЇДЕ» (наряд Ц-2). Вітрина ремонту складається з
    трьох джерел: слоти структурних блокерів, вузли напруги й слоти повтору K-VAR-01. Слот,
    який назвала знахідка своїм вікном, у неї потрапляв лише випадком — тобто моделі просили
    поставити гучніший акцент і не давали жодної речі, якою це зробити. Рівно той самий
    дефект уже лагодився тут для K-VAR-01 (25.09.2026, живий прогін «Ір, собаки», сід 13):
    «іншу річ у цьому слоті моделі було взяти нізвідки». Канал названий, а не загальний для
    всіх правил: ширший вплив на вітрину без виміру означав би змінити ремонт усіх правил
    одним рухом.

    `образи` — записи образів, як їх бачить `вердикт_моделі.вердикт_v1`. ДВА ІМЕНИ ОДНОГО
    ПОЛЯ, І ОБИДВА ЖИВІ: сира знахідка несе `запит_у_каталог` (так її будує `реєстр_сила._зн`),
    а після `суд_огляд.для_стиліста` те саме вікно зветься `вікно` — і саме ця форма доїжджає
    до вердикту через `композитор_оцінка._оцінити`. Читати лише одне ім'я означало б нічого не
    знайти на живому шляху (виміряно: на пакетному пулі сцени «клуб» слот запиту читався
    порожнім рівно через це). У рядок вердикту (`знахідки_вердикту`) вікно вже не переживає,
    тому канал і бере СИРІ знахідки образу, а не рядки."""
    слоти = []
    for о in (образи or []):
        # ЗАПИС УЖЕ МОЖЕ НЕСТИ ГОТОВИЙ СЛОТ: `міст_відповіді` знімає його полем
        # `_слоти_мети`, поки знахідка ще сира, — бо в рядок дроту вікно не переживає.
        for с in ((о or {}).get("_слоти_мети") or []):
            if с and с not in слоти:
                слоти.append(str(с))
        for z in ((о or {}).get("знахідки") or []):
            if not isinstance(z, dict) or z.get("правило") != ПРАВИЛО:
                continue
            с = ((z.get("запит_у_каталог") or z.get("вікно")) or {}).get("слот")
            if с and с not in слоти:
                слоти.append(str(с))
    return слоти
