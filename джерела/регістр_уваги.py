# ── ДЕ РІЧ ВЕДЕ ПОГЛЯД (ФОКУС-3) ─────────────────────────────────────────────────────────
# Сережки біля обличчя ведуть погляд угору, геть від живота: корпус каже
# поставити те, що вирізняється, туди, де має бути фокус (K-COL-08 «put advancing properties
# where the focus should be»; K-CRA-02 — фокус «where the eye should go on this body»), а
# мета «приховати» — напрям уваги ВІД зони (тема-6 §1.6). Коли вона назвала зону
# (`мета_зони` паспорта, код `goal_zones`), знахідка лишається лише на речах, що відкривають
# цю зону (`outfit.зони_речі`: її вимір з полів і країв речі); решта працює на мету.
# Де річ на ній, таблиця слотів тут не каже (корінь Е3-місце-речі): ні «верх — на животі», ні «пояс — на
# талії», ні «намисто — на грудях» без виміру чи слова стилістки не стверджується. Місце речі —
# запис `місце_речі` (`місце_речі.записати`): «не видно» (стилістка) знімає річ із суду; невідомо,
# де річ відносно зони, — правило мовчить, а не підставляє слот. Без зони судиться увесь образ.


def відомі_зони(зони_мети):
    """Зони мети, які знає внутрішня мова (`goal_zone`), множиною; чуже слово відкидається."""
    return {str(з).strip().lower() for з in (зони_мети or ())} & set(_ВМ.ТАБЛИЦЯ["goal_zone"].values())


def мета_образу(мета):
    """Мета для правил УСЬОГО образу (гармонізація, палітра, посадка, доза «на межі») — сама вісь уваги.

    Мета має дві осі (рядок 5211, рішення власника 15.10): зони («відвести погляд від…») — окрема плитка з
    будь-якою увагою, і увагу всього образу вони не гасять: «приховати» + зона — «тихо всім образом і ще
    зона». Зони судять лише речі в зоні (`на_мету`, `ранг_уваги`, R-CHEV-08), тому сюди не передаються.
    Старий запис «приховати» + зона (до 15.10 — лише зона) переводить на осі `паспорт_нагоди.мета_на_осі` ще
    в шві: увага «невідомо», зони лишаються."""
    return мета


def на_мету(слот, r=None, тіло=None, зони_мети=None):
    """Чи судить мета цю річ: True — відкриває зону мети; False — її не видно; None — невідомо.

    Зон нема чи жодна не знайома — судиться видима річ усього образу. Місце речі —
    запис `місце_речі` (елемент образу несе його сам; для речі поза елементами пишемо тут), зону, яку
    річ відкриває, дає `outfit.зони_речі` з її полів; сталої слота нема. Незнання — мовчання: річ без
    виміру й слова про зону не судиться. `слот` лишено в підписі для викликів, правило його не читає."""
    зони = відомі_зони(зони_мети)
    if not (isinstance(r, dict) and r):
        return None
    запис = r.get("місце_речі") or _М.записати(r)
    видно = запис.get("видно")
    if видно is None:
        return None
    if видно == 0.0:
        return False
    if not зони:
        return True
    відкриті, _чому = _O.зони_речі(r, тіло)
    if відкриті is None:
        return None
    if зони & set(відкриті):
        return True
    return None


def гучність_уваги(L, C):
    """C* × (L*/50) — те саме мірило, що `формальність.нагода_палітра` (K-KOH-08).

    Не хрома: бордо (C* 27–42) працює саме тому, що затемнене, а фуксія тієї ж хроми —
    ні. Калібрування — у `occasion.РЕЄСТР["вечірня_гучність"]`.

    ⚠ ІМ'Я НАВМИСНО НЕ `гучність`: `колір_річ.гучність(lab)` — ІНШЕ мірило (абсолютна C*
    і біт `гучний` для бюджету хроми K-COL-02). Два різні питання про одне слово; тут
    питання «чи перетягує увагу», там — «чи це високонасичений елемент»."""
    return float(C) * (float(L) / 50.0)


def стеля():
    """Стеля гучності «не перетягувати увагу» — ЧИТАЄТЬСЯ з `формальність`, не копія."""
    return float(_ПОДІЯ.РЕЄСТР["вечірня_гучність"]["val"])


def смуги():
    """Смуги, проти яких калібрувалась стеля (K-KOH-08) — теж ЧИТАЮТЬСЯ з `формальність`.

    {тихі: (23, 32), гучні: (62, 87), хрома_гучних: (64, 86), L_темних: (15, 45)} — числа
    самих джерел: рекомендовані як тиха порада бордо/вино/теракота дають гучність 23–32,
    проблемні (яскраво-червоний, фуксія, кобальт, гірчиця) — 62–87 при хромі C* 64–86 і
    світлоті ВИЩЕ темної смуги 15–45.

    НАВІЩО ЦЕ ТУТ, КОЛИ Є СТЕЛЯ (наряд Ц-2). Стеля відповідає на питання «чи над межею»,
    а знахідці потрібне друге питання — «наскільки»: без ШИРИНИ смуги нормування сили
    доводилось брати зі стелі плюс власне число (тут доти стояло `/ 40.0`, якого в корпусі
    нема ніде). Тепер обидва кінці — з тих самих джерел, що й стеля."""
    с = _ПОДІЯ.РЕЄСТР["смуги"]["val"]
    return {k: (float(v[0]), float(v[1])) for k, v in с.items()}


def _L_C(r):
    """(L*, C*) речі чи елемента для гучності уваги або (None, None) — коли кольору немає чим виміряти.

    Вимір — точка; читач один на систему — `колір_річ.гучність`, той самий, яким `outfit.елементи`
    збагачує кожен елемент образу. Колір зі слова — межі вікна: гучність C*·L*/50 росте
    з обома осями, тож вікно, все над стелею (`гучність_меж` «так»), дає свій найтихіший кут (L0, C0),
    все під стелею («ні») — найгучніший (L1, C1): обидва — нижня межа сили знахідки. Вікно по обидва
    боки стелі — (None, None), як невиміряна річ."""
    т = _КР.точка_кольору(r)
    if т is not None:
        г = _КР.гучність(т)
        return г.get("L"), г.get("C")
    м = _КР.межі_кольору(r) if _КР.не_вимір(r) is not None else None
    бік = _КР.гучність_меж(r, стеля=стеля()) if м is not None else None
    return (м[0], м[2]) if бік == "так" else (м[1], м[3]) if бік == "ні" else (None, None)


def _акцентний_слот(E, схема=None):
    """Слот образу, у якому колір і має стояти акцентом, — або None.

    ЧОМУ НЕ «НАЙБІЛЬША ПЛОЩА» (наряд Ц-2). Доти знахідка «увагу не тримає ніщо» називала
    річ із найбільшою площею — і сама ж собі суперечила ремонтом «гучніший колір в одному
    слоті, акцент, а не весь образ»: найбільша площа — це і є весь образ. Роль кольору в
    образі вже оголошена в `палітра_схеми` (`ДЕФОЛТ_РОЛЕЙ`, і власні `ролі` схеми через
    `розподіл_ролей`): домінанта тримає поле, секундант дає крок світлоти, акцент несе
    хрому. Тому слот запиту — акцентний слот ЦІЄЇ схеми, а не наш здогад.

    Схема, якої `СХЕМИ` не знає (її не передали, прилад, проба), — не помилка: тоді роль
    беруться з дефолтної мапи, тобто рівно те, що робить `розподіл_ролей` без власних
    ролей схеми."""
    слоти = [str(e.get("слот")) for e in (E or []) if e.get("слот")]
    if not слоти:
        return None
    S = _ПС.СХЕМИ.get(схема)
    ролі = (_ПС.розподіл_ролей(tuple(слоти), S) if S
            else {с: _ПС.ДЕФОЛТ_РОЛЕЙ.get(с, "акцент") for с in слоти})
    акцентні = [с for с in слоти if ролі.get(с) == "акцент"]
    return акцентні[0] if акцентні else None


def свідки_помітності(r, тіло=None):
    """(свідки, виміряно) — чим саме ця річ тримає увагу.

    `свідки` — список рядків «що видно й з якого виміру»; порожній означає «жоден
    свідок не спрацював», а не «річ тиха»: друге значення каже, чи КОЛІР узагалі
    виміряно. Незнання не програє й не виграє — той самий принцип, що `_ранг_фото`
    в доборі пулу."""
    свідки = _свідки(r, тіло)
    return [с[2] for с in свідки], _L_C(r)[0] is not None


def _зони_кодами(зони_мети):
    """Зони мети кодами таблиці `zone` (ті самі, що в свідку `open_zone`), відсортовано."""
    return sorted(_ВМ.код("zone", з) or _ВМ.UNKNOWN for з in відомі_зони(зони_мети))


def _коди_свідків(свідки):
    """Значення заяви з уже відібраних свідків `_свідки` (без кольору): те саме, що `свідки_кодами`."""
    з = {}
    for код, знач, _р in свідки:
        if код != "loudness":
            з.setdefault("witnesses", []).append(код)
            з.update(знач)
    return з




def _свідки(r, тіло=None):
    """[(код свідка, значення заяви, рядок звіту)] — одне джерело для `свідки_помітності` (рядки
    звіту) і `свідки_кодами` (дріт): поріг і вимір у двох видах не розходяться."""
    свідки = []
    L, C = _L_C(r)
    if L is not None:
        г, ст = гучність_уваги(L, C), стеля()
        if г > ст:
            свідки.append(("loudness", dict(loudness=round(г), ceiling=round(ст)),
                           "гучність %.0f (C*%.0f × L*%.0f/50) над стелею %.0f" % (г, C, L, ст)))
    зони, _чому = _O.зони_речі(r, тіло)
    if зони:
        свідки.append(("open_zone", dict(zones=sorted(_ВМ.код("zone", з) or _ВМ.UNKNOWN for з in зони)),
                       "відкриває %s" % ", ".join(sorted(зони))))
    оздоба = _ТР.святкова_оздоба(r)
    if оздоба:
        свідки.append(("festive_trim", {}, "святкова оздоба: %s" % оздоба))
    бл = _ТР.свідки_блиску(r)
    кл = max(бл.get("клас") or 0, бл.get("блиск") or 0)
    if кл >= _ТР.БЛИСК_ГЛЯНЕЦЬ:
        свідки.append(("shine", dict(shine_class=кл), "блиск класу %d" % кл))
    return свідки


def _судить_річ(мета, слот, r, тіло, зони_мети):
    """Чи стоїть річ під напрямом «тихо»: за увагою «приховати» — увесь образ; за будь-якою
    іншою увагою з названою зоною — лише річ, що `на_мету` (у зоні, веде до неї погляд чи її відкриває)."""
    if мета == "приховати":
        return на_мету(слот, r, тіло)
    if відомі_зони(зони_мети):
        return на_мету(слот, r, тіло, зони_мети)
    return False


def ранг_уваги(r, мета, тіло=None, слот=None, зони_мети=None):
    """Ранг речі в пулі за метою образу: 0 — уперед, більше — назад.

    «приховати» — кількість свідків помітності (тиха й невиміряна річ обидві 0, тобто
    незнання не програє); «експресія» — дзеркало: −кількість (помітна річ виходить
    уперед, тиха й невиміряна стоять на 0). Поза цими двома метами — 0 всім, тобто
    порядок не рухається ні на йоту.

    Її явний вибір (п.9), невідома позиція відносно зони мети та невідома видимість — 0:
    правило не рухає річ, якої не може судити. Річ, якої не видно, теж не рухається."""
    if not isinstance(r, dict) or (str(мета or "") not in МЕТИ_РЕГІСТРУ and not відомі_зони(зони_мети)):
        return 0
    if її_вибір(r):
        return 0
    if на_мету(слот, r, тіло) is not True:
        return 0
    # Зона «відвести погляд від…» діє з будь-якою увагою: річ у зоні йде назад, решта — за увагою.
    судить = _судить_річ(мета, слот or r.get("слот"), r, тіло, зони_мети)
    if судить is None:
        return 0
    if судить:
        return len(свідки_помітності(r, тіло)[0])
    return -len(свідки_помітності(r, тіло)[0]) if мета == "експресія" else 0


def нота_пулу(речі, мета, тіло=None, слот=None, зони_мети=None):
    """Заява для ноти слота: скільком речам мета змінила місце, або None.

    Це технічна заява для ноти слота, а не текст для жінки й моделі: вона їде у
    `ноти_слотів` звіту власника — кошик В п.12. Напрям («після» / «перед») читається
    з коду мети."""
    if str(мета or "") not in МЕТИ_РЕГІСТРУ and not відомі_зони(зони_мети):
        return None
    рухомі = [r for r in (речі or []) if ранг_уваги(r, мета, тіло, слот, зони_мети)]
    if not рухомі:
        return None
    return _ВМ.заява("goal_moves_loud_items_in_kind",
                     goal=_ВМ.код_або_невідомо("goal", мета),
                     moved=len(рухомі), of=len(речі or []))


def _річ_елемента(елемент, за_ід):
    """Річ із записом місця елемента образу: він знає шар і видимість у цьому стані."""
    річ = за_ід.get(елемент.get("річ")) or {}
    if елемент.get("місце_речі") is not None:
        return dict(річ, місце_речі=елемент["місце_речі"])
    return річ


def знахідка_уваги(E, речі, мета, тіло=None, схема=None, зони_мети=None):
    """Знахідки R-CHEV-08 за метою образу. Список (порожній — мета напряму не дає).

    ПРИХОВАТИ — на кожну річ, чия гучність над стелею: сила за виміром × площа, рівно як
    K-KOH-08 (`формальність.нагода_палітра`), плюс оздоба й блиск окремими свідками
    регістру «репліка». ЕКСПРЕСІЯ — дзеркало: коли образу не тримає увагу НІЩО — ні колір,
    ні оздоба, ні блиск, ні відкрита зона.

    Сила за «експресією» — наскільки найгучніша річ не дістає стелі,
    нормовано шириною калібрувальної смуги. Свідки помітності однакові для
    обох напрямів. Правило повертає вимір і пояснення без вікна ремонту:
    іншого складу воно не судило й кандидатів добору не має.

    ЗОНА МЕТИ (ФОКУС-3): при «приховати» з названою зоною (`зони_мети`) обидві
    знахідки стоять лише на речах, які `на_мету` — річ, що відводить погляд від зони, працює
    на мету. Зона — окрема плитка з будь-якою увагою: за «звично» знахідки стоять
    лише в зоні, за «помітно» — у зоні, а «увагу не тримає ніщо» рахує речі поза зоною.

    НЕ ГЕЙТ НІ В ОДНОМУ БОЦІ: мета — напрям поради, а не заборона (тема-6 §1.6), і п.9
    аудит/ПРОДУКТ.md не дає замикати жінці вибір. Її річ (п.9) знахідки не дістає."""
    м = str(мета or "")
    if м not in МЕТИ_РЕГІСТРУ and not відомі_зони(зони_мети):
        return []
    за_ід = {r.get("id"): r for r in (речі or []) if isinstance(r, dict) and r.get("id")}
    невідоме_місце = False
    видимі = []
    for e in (E or []):
        r = _річ_елемента(e, за_ід)
        видно = на_мету(e.get("слот"), r, тіло)
        if видно is None:
            невідоме_місце = True
        if видно is True:
            видимі.append(e)
            if _судить_річ(м, e.get("слот"), r, тіло, зони_мети) is None:
                невідоме_місце = True
    E = видимі
    ст, зн = стеля(), []
    гучні = []
    # L* і C* — тим самим `_L_C`, що свідки пулу: вимір — точкою (`outfit.елементи` кладе її елементу),
    # вікно слова — межами. Вікно по обидва боки стелі «приховати» — «без входу».
    без_входу = []
    for e in (E or []):
        r = _річ_елемента(e, за_ід)
        L, C = _L_C(e)
        if L is None or C is None:
            мк = _КР.межі_кольору(e) if _КР.не_вимір(e) is not None else None
            # «без входу» — лише коли найгучніший кут вікна дав би вагу понад підлогу (та сама сила, що нижче)
            if мк is not None and (м == "приховати" or відомі_зони(зони_мети)) \
                    and not (r and її_вибір(r)) and _судить_річ(м, e.get("слот"), r, тіло, зони_мети) \
                    and not _РЕЄСТР.під_підлогою(
                        min(1.0, (гучність_уваги(мк[1], мк[3]) - ст) / (смуги()["гучні"][1] - ст))
                        * min(1.0, (0.25 if e.get("площа") is None else e["площа"]) / 0.25)):
                без_входу.append((e,))
            continue
        г = гучність_уваги(L, C)
        if г > ст:
            гучні.append((e, r, г, float(L), float(C)))
    # Гілка «тихо» — за увагою «приховати» на всьому образі, за зоною з будь-якою увагою — у зоні.
    if м == "приховати" or відомі_зони(зони_мети):
        for e, r, г, L, C in гучні:
            if r and її_вибір(r):
                continue
            if _судить_річ(м, e.get("слот"), r, тіло, зони_мети) is not True:
                continue
            пл = e.get("площа")
            # ШИРИНА СМУГИ — З КОРПУСУ, А НЕ «/ 40» (наряд Ц-2): повна сила там, де гучність
            # дійшла до верху смуги, яку джерела назвали проблемною (87). Доти тут стояло
            # число, якого в корпусі нема ніде, — близьке до 87 − 45, але не назване.
            зверху = смуги()["гучні"][1] - ст
            сила_нп = round(min(1.0, (г - ст) / зверху) * min(1.0, (0.25 if пл is None else пл) / 0.25), 2)
            зн.append(dict(_РЕЄСТР.зн(
                ПРАВИЛО, "soft" if сила_нп >= _РЕЄСТР.C["нп_межа_soft"] else "hint",
                ("колір тримає увагу, а мета образу — приховати" if м == "приховати" else
                 "колір тримає увагу в зоні, від якої вона відводить погляд"), [e.get("річ")],
                "гучність %.0f (C*%.0f × L*%.0f/50) проти стелі %.0f%s; мета зі слів жінки "
                "про цей вихід — «приховати» (тема-6 §1.6: вісь «увага не привертається ↔ "
                "привертається» міняє НАПРЯМ поради)"
                % (г, C, L, ст, (" при площі %.0f%%" % (100 * пл)) if пл is not None
                   else " (площі нема — сила стоїть на самому вимірі кольору)"),
                ламається="мета — напрям, не вето: її явний вибір цієї речі знімає знахідку "
                          "(п.9); поріг калібрований на нагоді, де питання те саме (K-KOH-08)",
                поріг=ст, вимір=г,
                # Дріт моделі везе заяви кодами, а `суть` і `ремонт` — лише звіту власника.
                # Заява «мета — приховати» стосується лише уваги «приховати»; з іншою увагою
                # потрібна заява про зону.
                заяви=[_ВМ.заява("colour_holds_attention_goal_conceal", loudness=round(г), ceiling=round(ст),
                                 **({"area_pct": round(100 * пл)} if пл is not None else {}))
                       if м == "приховати" else
                       _ВМ.заява("colour_holds_attention_in_goal_zone", loudness=round(г), ceiling=round(ст),
                                 zones=_зони_кодами(зони_мети),
                                 **({"area_pct": round(100 * пл)} if пл is not None else {}))]),
                сила_нп=сила_нп,
                сила_нп_джерело="вимір (гучність C*×L* над стелею × площа; повна сила — "
                                "верх проблемної смуги K-KOH-08)"))
        for e in (E or []):
            r = _річ_елемента(e, за_ід)
            if not r or її_вибір(r):
                continue
            if _судить_річ(м, e.get("слот"), r, тіло, зони_мети) is not True:
                continue
            # За зоною мети свідок «відкриває» важить, лише коли річ відкриває САМЕ зону мети:
            # топ із відкритими руками живота не відкриває (Г3: топи за `open_zone arms` при зоні «живіт»)
            сз = [с for с in _свідки(r, тіло) if с[0] != "loudness"
                  and (с[0] != "open_zone" or м == "приховати" and not відомі_зони(зони_мети)
                       or set(с[1].get("zones") or ()) & set(_зони_кодами(зони_мети)))]
            інші = [с[2] for с in сз]
            if not інші:
                continue
            # Чи лежить річ на самій зоні (пояс на животі), код не знає без виміру й слова стилістки: таблиці
            # слота нема (Е3-місце-речі), тому свідок словом — завжди `hint`.
            зн.append(dict(_РЕЄСТР.зн(
                ПРАВИЛО, "hint",
                ("річ помітна не кольором, а собою, а мета образу — приховати" if м == "приховати" else
                 "річ помітна собою в зоні, від якої вона відводить погляд"), [e.get("річ")],
                "%s; мета зі слів жінки — %s (тема-6 §1.6)" % ("; ".join(інші), "«приховати»" if м == "приховати"
                                                              else "відвести погляд від зони"),
                ламається="свідки грубі: `outfit.зони_речі` не бачить глибини вирізу, "
                          "`свідки_блиску` — блиску без слова крамниці й без фото. Її явний "
                          "вибір знімає знахідку (п.9)",
                заяви=[_ВМ.заява("item_draws_eye_by_itself_goal_conceal" if м == "приховати"
                                 else "item_draws_eye_by_itself_in_goal_zone", **_коди_свідків(сз))]),
                сила_нп=_РЕЄСТР.КАТ_У_НП["hint"],
                сила_нп_джерело="свідок словом крамниці — числа під ним нема"))
    if без_входу:
        зн.append(_КР.без_входу_кольору(ПРАВИЛО, без_входу, перевірка="cannot_tell_colour_holds_attention"))
    # МІРЯТИ НІЧИМ ХОЧ НА ОДНІЙ РЕЧІ — ЗНАХІДКИ НЕМА (та сама політика, що доти: «образ із
    # невиміряним кольором знахідки не дістає взагалі»). Умова стала ЯВНОЮ, бо нижче тепер
    # стоїть вимір, а не константа: сказати «ніщо не тримає увагу», не побачивши кольору
    # однієї з речей, означало б вигадати вимір. Порожній образ теж не судиться. Вікно слова
    # по обидва боки стелі — не мовчання, а «без входу» з полем; колір без жодного
    # входу — як доти, мовчки.
    _LC = [_L_C(e) for e in (E or [])]
    if м == "експресія" and E and not невідоме_місце \
            and not [г for г in гучні if _судить_річ(м, г[0].get("слот"), г[1], тіло, зони_мети) is False]:
        # СВІДКИ НЕ КОЛЬОРОМ — ТІ САМІ, ЩО В «ПРИХОВАТИ» (вада 3 в докстрінгу): пайєтки,
        # блиск і відкрита зона тримають увагу без жодної хроми, і на такому образі мета
        # «експресія» вже вдоволена.
        тримає_собою = []
        for e in (E or []):
            r = _річ_елемента(e, за_ід)
            if not r:
                continue
            інші = [с for с in свідки_помітності(r, тіло)[0] if not с.startswith("гучність")]
            if інші:
                тримає_собою.append((e.get("річ"), інші))
        if тримає_собою:
            return зн
        if any(L is None for L, _ in _LC):
            if all(L is not None or _КР.не_вимір(e) is not None for e, (L, _) in zip(E, _LC)):
                зн.append(_КР.без_входу_кольору(ПРАВИЛО, [(e,) for e, (L, _) in zip(E, _LC) if L is None],
                                                перевірка="cannot_tell_colour_holds_attention"))
            return зн
        макс = max(гучність_уваги(L, C) for L, C in _LC)
        тихий_низ = смуги()["тихі"][0]
        # ВИМІР, А НЕ КОНСТАНТА (вада 2): повна сила там, де найгучніша річ образу тихіша
        # за все, що джерела називають тихою ПОРАДОЮ (23); нуль — там, де вона на стелі.
        сила_нп = round(min(1.0, max(0.0, (ст - макс) / (ст - тихий_низ))), 2)
        слот = _акцентний_слот(E, схема)
        носій = next((e.get("річ") for e in E if e.get("слот") == слот), None) \
            or max(E, key=lambda e: (e.get("площа") or 0)).get("річ")
        зн.append(dict(_РЕЄСТР.зн(
            ПРАВИЛО, "soft" if сила_нп >= _РЕЄСТР.C["нп_межа_soft"] else "hint",
            "увагу не тримає ніщо, а мета образу — експресія", [носій],
            "найгучніша річ образу дає %.0f (C* × L*/50) проти стелі %.0f, і жодна річ не "
            "тримає увагу ні оздобою, ні блиском, ні відкритою зоною; мета зі слів жінки про "
            "цей вихід — «експресія» (тема-6 §1.6: вісь уваги міняє НАПРЯМ поради)"
            % (макс, ст),
            ламається="мета — напрям, не вимога: тихий образ на «експресію» не блокується, і "
                      "її явний вибір речі знахідки не скасовує лише тому, що образ тихий "
                      "(п.9 діє на річ, а ця знахідка — про образ цілий); свідки «собою» "
                      "грубі — блиску без слова крамниці й глибини вирізу код не бачить",
            поріг=ст, вимір=макс,
            заяви=[_ВМ.заява("nothing_holds_attention_goal_express", loudness=round(макс), ceiling=round(ст))]),
            сила_нп=сила_нп,
            сила_нп_джерело="вимір (наскільки найгучніша річ не дістає стелі, нормовано "
                            "шириною тихої смуги K-KOH-08)"))
    return зн


def слоти_ремонту(образи):
    """Слоти, які просить R-CHEV-08, — для вітрини ремонту (`повнота_образу.вітрина_ремонту`).

    ЧОМУ ЦЕ ОКРЕМИЙ КАНАЛ, А НЕ «САМО ДОЇДЕ» (наряд Ц-2). Вітрина ремонту складається з
    трьох джерел: слоти структурних блокерів, вузли напруги й слоти повтору K-VAR-01. Слот,
    який назвала знахідка своїм вікном, у неї потрапляв лише випадком — тобто моделі просили
    поставити гучніший акцент і не давали жодної речі, якою це зробити. Це той самий
    клас дефекту, що й для K-VAR-01: «іншу річ у цьому слоті моделі було
    взяти нізвідки». Канал названий, а не загальний для
    всіх правил: ширший вплив на вітрину без виміру означав би змінити ремонт усіх правил
    одним рухом.

    `образи` — записи образів, як їх бачить `вердикт_моделі.вердикт_v1`. ДВА ІМЕНИ ОДНОГО
    ПОЛЯ, І ОБИДВА ЖИВІ: сира знахідка несе `запит_у_каталог` (так її будує `реєстр_сила.зн`),
    а після `суд_огляд.для_стиліста` те саме вікно зветься `вікно` — і саме ця форма доїжджає
    до вердикту через `композитор_оцінка.оцінити`. Читати лише одне ім'я означало б нічого не
    знайти на живому шляху (виміряно: на пакетному пулі сцени «клуб» слот запиту читався
    порожнім рівно через це). У рядок вердикту (`знахідки_вердикту`) вікно вже не переживає,
    тому канал і бере СИРІ знахідки образу, а не рядки."""
    слоти = []
    for о in (образи or []):
        # ЗАПИС УЖЕ МОЖЕ НЕСТИ ГОТОВИЙ СЛОТ: `міст_відповіді` знімає його полем
        # `_слоти_мети`, поки знахідка ще сира, — бо в рядок дроту вікно не переживає.
        for с in ((о or {}).get("_слоти_мети") or []):
            if с and с not in слоти:
                слоти.append(str(с))
        for z in ((о or {}).get("знахідки") or []):
            if not isinstance(z, dict) or z.get("правило") != ПРАВИЛО:
                continue
            с = ((z.get("запит_у_каталог") or z.get("вікно")) or {}).get("слот")
            if с and с not in слоти:
                слоти.append(str(с))
    return слоти
