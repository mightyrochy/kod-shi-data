def на_мету(слот, r=None, тіло=None, зони_мети=None):
    """Чи судить мета «приховати» цю річ: True — річ у зоні мети, веде до неї погляд або
    її відкриває; False — річ відводить погляд від зони, тобто працює на мету.

    Зон нема чи жодна не знайома (`ЗОНА_МЕТИ_СЛОТИ`) — True: мета без місця судить увесь
    образ, як доти. Слота нема — теж True: де річ, невідомо, і незнання не знімає знахідки."""
    зони = {str(з).strip().lower() for з in (зони_мети or ())} & set(ЗОНА_МЕТИ_СЛОТИ)
    if not зони or not слот:
        return True
    if any(слот in ЗОНА_МЕТИ_СЛОТИ[з] for з in зони):
        return True
    if isinstance(r, dict) and r:
        import outfit as _O
        return bool(зони & set(_O.зони_речі(r, тіло)[0] or ()))
    return False


def гучність_уваги(L, C):
    """C* × (L*/50) — те саме мірило, що `формальність.нагода_палітра` (K-KOH-08).

    Не хрома: бордо (C* 27–42) працює саме тому, що затемнене, а фуксія тієї ж хроми —
    ні. Калібрування — у `формальність.НАГОДА["reserved_white_evening"]`.

    ⚠ ІМ'Я НАВМИСНО НЕ `гучність`: `колір_річ.гучність(lab)` — ІНШЕ мірило (абсолютна C*
    і біт `гучний` для бюджету хроми K-COL-02). Два різні питання про одне слово; тут
    питання «чи перетягує увагу», там — «чи це високонасичений елемент»."""
    return float(C) * (float(L) / 50.0)


def стеля():
    """Стеля гучності «не перетягувати увагу» — ЧИТАЄТЬСЯ з `формальність`, не копія."""
    from формальність import НАГОДА
    return float(НАГОДА["reserved_white_evening"]["стеля_гучності"])


def смуги():
    """Смуги, проти яких калібрувалась стеля (K-KOH-08) — теж ЧИТАЮТЬСЯ з `формальність`.

    {тихі: (23, 32), гучні: (62, 87), хрома_гучних: (64, 86), L_темних: (15, 45)} — числа
    самих джерел: рекомендовані як тиха порада бордо/вино/теракота дають гучність 23–32,
    проблемні (яскраво-червоний, фуксія, кобальт, гірчиця) — 62–87 при хромі C* 64–86 і
    світлоті ВИЩЕ темної смуги 15–45.

    НАВІЩО ЦЕ ТУТ, КОЛИ Є СТЕЛЯ (наряд Ц-2). Стеля відповідає на питання «чи над межею»,
    а знахідці потрібне друге питання — «наскільки»: без ШИРИНИ смуги нормування сили
    доводилось брати зі стелі плюс власне число (тут доти стояло `/ 40.0`, якого в корпусі
    нема ніде). Тепер обидва кінці — з тих самих джерел, що й стеля."""
    from формальність import НАГОДА
    с = НАГОДА["reserved_white_evening"]["гучність_смуги"]
    return {k: (float(v[0]), float(v[1])) for k, v in с.items()}


def _L_C(r):
    """(L*, C*) речі або (None, None) — коли кольору немає чим виміряти.

    Читач один на систему — `колір_річ.гучність`, той самий, яким `outfit.елементи`
    збагачує кожен елемент образу (`outfit.py:493`). Тому число тут і число в суді —
    те саме число, а не дві реалізації lch."""
    lab = r.get("lab") if isinstance(r, dict) else None
    if not lab or len(lab) < 3:
        return None, None
    import колір_річ as _КР
    г = _КР.гучність(tuple(lab))
    return г.get("L"), г.get("C")


def її_вибір(r):
    """Чи цю річ поставило в пул слово жінки (п.9) — один предикат на систему.

    ⚠ ЧЕСНО ПРО ВХІД: мітки (`за_бажанням`, утримання, `власна`, `закріплена`) ставить
    `міст_пакет` ПІСЛЯ добору слота, тож у ранзі пулу цей предикат майже завжди False —
    п.9 там тримає інше (див. шапку модуля). У суді мітки вже стоять, і тут він живий."""
    import порядок_запиту as _ПЗ
    return _ПЗ.ярус(r) == 0


def _акцентний_слот(E, схема=None):
    """Слот образу, у якому колір і має стояти акцентом, — або None.

    ЧОМУ НЕ «НАЙБІЛЬША ПЛОЩА» (наряд Ц-2). Доти знахідка «увагу не тримає ніщо» називала
    річ із найбільшою площею — і сама ж собі суперечила ремонтом «гучніший колір в одному
    слоті, акцент, а не весь образ»: найбільша площа — це і є весь образ. Роль кольору в
    образі вже оголошена в `палітра_схеми` (`ДЕФОЛТ_РОЛЕЙ`, і власні `ролі` схеми через
    `розподіл_ролей`): домінанта тримає поле, секундант дає крок світлоти, акцент несе
    хрому. Тому слот запиту — акцентний слот ЦІЄЇ схеми, а не наш здогад.

    Схема, якої `СХЕМИ` не знає (її не передали, прилад, проба), — не помилка: тоді роль
    беруться з дефолтної мапи, тобто рівно те, що робить `розподіл_ролей` без власних
    ролей схеми."""
    import палітра_схеми as _ПС
    слоти = [str(e.get("слот")) for e in (E or []) if e.get("слот")]
    if not слоти:
        return None
    S = _ПС.СХЕМИ.get(схема)
    ролі = (_ПС.розподіл_ролей(tuple(слоти), S) if S
            else {с: _ПС.ДЕФОЛТ_РОЛЕЙ.get(с, "акцент") for с in слоти})
    акцентні = [с for с in слоти if ролі.get(с) == "акцент"]
    return акцентні[0] if акцентні else None


def свідки_помітності(r, тіло=None):
    """(свідки, виміряно) — чим саме ця річ тримає увагу.

    `свідки` — список рядків «що видно й з якого виміру»; порожній означає «жоден
    свідок не спрацював», а не «річ тиха»: друге значення каже, чи КОЛІР узагалі
    виміряно. Незнання не програє й не виграє — той самий принцип, що `_ранг_фото`
    в доборі пулу."""
    свідки = _свідки(r, тіло)
    return [с[2] for с in свідки], _L_C(r)[0] is not None


def свідки_кодами(r, тіло=None):
    """Ті самі свідки, що `свідки_помітності`, крім кольору, — значеннями заяви (п.12, рядок 1650):
    `witnesses` — коди свідків (open_zone · festive_trim · shine), `zones` — зони кодами таблиці
    `zone`, `shine_class` — клас блиску. Слово оздоби крамниці лишається в рядку звіту, на дріт не їде."""
    з = {}
    for код, знач, _р in _свідки(r, тіло):
        if код != "loudness":
            з.setdefault("witnesses", []).append(код)
            з.update(знач)
    return з


def _свідки(r, тіло=None):
    """[(код свідка, значення заяви, рядок звіту)] — одне джерело для `свідки_помітності` (рядки
    звіту) і `свідки_кодами` (дріт): поріг і вимір у двох видах не розходяться."""
    import траурний_регістр as _ТР
    import outfit as _O
    import внутрішня_мова as _ВМ
    свідки = []
    L, C = _L_C(r)
    if L is not None:
        г, ст = гучність_уваги(L, C), стеля()
        if г > ст:
            свідки.append(("loudness", dict(loudness=round(г), ceiling=round(ст)),
                           "гучність %.0f (C*%.0f × L*%.0f/50) над стелею %.0f" % (г, C, L, ст)))
    зони, _чому = _O.зони_речі(r, тіло)
    if зони:
        свідки.append(("open_zone", dict(zones=sorted(_ВМ.код("zone", з) or _ВМ.UNKNOWN for з in зони)),
                       "відкриває %s" % ", ".join(sorted(зони))))
    оздоба = _ТР.святкова_оздоба(r)
    if оздоба:
        свідки.append(("festive_trim", {}, "святкова оздоба: %s" % оздоба))
    бл = _ТР.свідки_блиску(r)
    кл = max(бл.get("клас") or 0, бл.get("блиск") or 0)
    if кл >= _ТР.БЛИСК_ГЛЯНЕЦЬ:
        свідки.append(("shine", dict(shine_class=кл), "блиск класу %d" % кл))
    return свідки


def ранг_уваги(r, мета, тіло=None, слот=None, зони_мети=None):
    """Ранг речі в пулі за метою образу: 0 — уперед, більше — назад.

    «приховати» — кількість свідків помітності (тиха й невиміряна річ обидві 0, тобто
    незнання не програє); «експресія» — дзеркало: −кількість (помітна річ виходить
    уперед, тиха й невиміряна стоять на 0). Поза цими двома метами — 0 всім, тобто
    порядок не рухається ні на йоту.

    Її явний вибір (п.9) — завжди 0: правило його не відсуває. Річ поза зоною мети
    (`на_мету`, рядок 1520) — теж 0: вона відводить погляд від зони, яку жінка ховає."""
    if not isinstance(r, dict) or str(мета or "") not in МЕТИ_РЕГІСТРУ:
        return 0
    if її_вибір(r):
        return 0
    if мета == "приховати" and not на_мету(слот or r.get("слот"), r, тіло, зони_мети):
        return 0
    свідки, _виміряно = свідки_помітності(r, тіло)
    return len(свідки) if мета == "приховати" else -len(свідки)


