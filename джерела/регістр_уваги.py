                поріг=ст, вимір=г,
                # П-6 (рядок 1650): дріт моделі везе заяви кодами, `суть`/`ремонт` — звіту власника
                заяви=[_ВМ.заява("colour_holds_attention_goal_conceal", loudness=round(г), ceiling=round(ст),
                                 **({"area_pct": round(100 * пл)} if пл is not None else {}))],
