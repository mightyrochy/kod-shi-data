# Мети, у яких вісь уваги має напрям. «лестити» й «невідомо» тут не діють НІЧИМ:
# флетеринг — про обличчя, а не про увагу, і мовчання жінки не є її вибором.
МЕТИ_РЕГІСТРУ = ("приховати", "експресія")


def гучність_уваги(L, C):
    """C* × (L*/50) — те саме мірило, що `формальність.нагода_палітра` (K-KOH-08).

    Не хрома: бордо (C* 27–42) працює саме тому, що затемнене, а фуксія тієї ж хроми —
    ні. Калібрування — у `формальність.НАГОДА["весілля_гість"]`.

    ⚠ ІМ'Я НАВМИСНО НЕ `гучність`: `колір_річ.гучність(lab)` — ІНШЕ мірило (абсолютна C*
    і біт `гучний` для бюджету хроми K-COL-02). Два різні питання про одне слово; тут
    питання «чи перетягує увагу», там — «чи це високонасичений елемент»."""
    return float(C) * (float(L) / 50.0)


def стеля():
    """Стеля гучності «не перетягувати увагу» — ЧИТАЄТЬСЯ з `формальність`, не копія."""
    from формальність import НАГОДА
    return float(НАГОДА["весілля_гість"]["стеля_гучності"])


def _L_C(r):
    """(L*, C*) речі або (None, None) — коли кольору немає чим виміряти.

    Читач один на систему — `колір_річ.гучність`, той самий, яким `outfit.елементи`
    збагачує кожен елемент образу (`outfit.py:493`). Тому число тут і число в суді —
    те саме число, а не дві реалізації lch."""
    lab = r.get("lab") if isinstance(r, dict) else None
    if not lab or len(lab) < 3:
        return None, None
    import колір_річ as _КР
    г = _КР.гучність(tuple(lab))
    return г.get("L"), г.get("C")


def її_вибір(r):
    """Чи цю річ поставило в пул слово жінки (п.9) — один предикат на систему.

    ⚠ ЧЕСНО ПРО ВХІД: мітки (`за_бажанням`, утримання, `власна`, `закріплена`) ставить
    `міст_пакет` ПІСЛЯ добору слота, тож у ранзі пулу цей предикат майже завжди False —
    п.9 там тримає інше (див. шапку модуля). У суді мітки вже стоять, і тут він живий."""
    import порядок_запиту as _ПЗ
    return _ПЗ.ярус(r) == 0


def свідки_помітності(r, тіло=None):
    """(свідки, виміряно) — чим саме ця річ тримає увагу.

    `свідки` — список рядків «що видно й з якого виміру»; порожній означає «жоден
    свідок не спрацював», а не «річ тиха»: друге значення каже, чи КОЛІР узагалі
    виміряно. Незнання не програє й не виграє — той самий принцип, що `_ранг_фото`
    в доборі пулу."""
    import траурний_регістр as _ТР
    import outfit as _O
    свідки = []
    L, C = _L_C(r)
    виміряно = L is not None
    if виміряно:
        г, ст = гучність_уваги(L, C), стеля()
        if г > ст:
            свідки.append("гучність %.0f (C*%.0f × L*%.0f/50) над стелею %.0f" % (г, C, L, ст))
    зони, _чому = _O.зони_речі(r, тіло)
    if зони:
        свідки.append("відкриває %s" % ", ".join(sorted(зони)))
    оздоба = _ТР.святкова_оздоба(r)
    if оздоба:
        свідки.append("святкова оздоба: %s" % оздоба)
    бл = _ТР.свідки_блиску(r)
    if (бл.get("клас") or 0) >= _ТР.БЛИСК_ГЛЯНЕЦЬ or (бл.get("блиск") or 0) >= _ТР.БЛИСК_ГЛЯНЕЦЬ:
        свідки.append("блиск класу %d" % max(бл.get("клас") or 0, бл.get("блиск") or 0))
    return свідки, виміряно


def ранг_уваги(r, мета, тіло=None):
    """Ранг речі в пулі за метою образу: 0 — уперед, більше — назад.

    «приховати» — кількість свідків помітності (тиха й невиміряна річ обидві 0, тобто
    незнання не програє); «експресія» — дзеркало: −кількість (помітна річ виходить
    уперед, тиха й невиміряна стоять на 0). Поза цими двома метами — 0 всім, тобто
    порядок не рухається ні на йоту.

    Її явний вибір (п.9) — завжди 0: правило його не відсуває."""
    if not isinstance(r, dict) or str(мета or "") not in МЕТИ_РЕГІСТРУ:
        return 0
    if її_вибір(r):
        return 0
    свідки, _виміряно = свідки_помітності(r, тіло)
    return len(свідки) if мета == "приховати" else -len(свідки)


def нота_пулу(речі, мета, тіло=None):
    """Рядок для ноти слота: скільком речам мета змінила місце, або None."""
    if str(мета or "") not in МЕТИ_РЕГІСТРУ:
        return None
    рухомі = [r for r in (речі or []) if ранг_уваги(r, мета, тіло)]
    if not рухомі:
        return None
    return ("мета «%s»: %d з %d речей слота несуть свідка помітності — стоять %s тихих "
            "(її явний вибір не рухається)"
            % (мета, len(рухомі), len(речі or []),
               "після" if мета == "приховати" else "перед"))


def знахідка_уваги(E, речі, мета, тіло=None):
    """Знахідки R-CHEV-08 за метою образу. Список (порожній — мета напряму не дає).

    ПРИХОВАТИ — на кожну річ, чия гучність над стелею: сила за виміром × площа, рівно як
    K-KOH-08 (`формальність.нагода_палітра`), плюс оздоба й блиск окремими свідками
    регістру «репліка». ЕКСПРЕСІЯ — дзеркало: коли ЖОДНА річ образу стелі не дістає, а
    колір виміряно, знахідка каже, що увагу не тримає ніщо.

    НЕ ГЕЙТ НІ В ОДНОМУ БОЦІ: мета — напрям поради, а не заборона (тема-6 §1.6), і п.9
    CLAUDE.md не дає замикати жінці вибір. Її річ (п.9) знахідки не дістає."""
    м = str(мета or "")
    if м not in МЕТИ_РЕГІСТРУ:
        return []
    import реєстр_правил as _РЕЄСТР
    за_ід = {r.get("id"): r for r in (речі or []) if isinstance(r, dict) and r.get("id")}
    ст, зн = стеля(), []
    гучні = []
    # L* і C* БЕРУТЬСЯ З ЕЛЕМЕНТА, не рахуються тут: `outfit.елементи` вже поклало їх
    # кожному (`e.update(колір_річ.гучність(e["lab"]))`), і саме ними міряє K-KOH-08.
    for e in (E or []):
        r = за_ід.get(e.get("річ")) or {}
        L, C = e.get("L"), e.get("C")
        if L is None or C is None:
            continue
        г = гучність_уваги(L, C)
        if г > ст:
            гучні.append((e, r, г, float(L), float(C)))
    if м == "приховати":
        for e, r, г, L, C in гучні:
            if r and її_вибір(r):
                continue
            пл = e.get("площа")
            сила_нп = round(min(1.0, (г - ст) / 40.0) * min(1.0, (пл or 0.25) / 0.25), 2)
            зн.append(dict(_РЕЄСТР._зн(
                "R-CHEV-08", "soft" if сила_нп >= _РЕЄСТР.C["нп_межа_soft"] else "hint",
                "колір тримає увагу, а мета образу — приховати", [e.get("річ")],
                "гучність %.0f (C*%.0f × L*%.0f/50) проти стелі %.0f%s; мета зі слів жінки "
                "про цей вихід — «приховати» (тема-6 §1.6: вісь «увага не привертається ↔ "
                "привертається» міняє НАПРЯМ поради)"
                % (г, C, L, ст, (" при площі %.0f%%" % (100 * пл)) if пл is not None
                   else " (площі нема — сила стоїть на самому вимірі кольору)"),
                ремонт=["та сама сім'я в глибшій версії — приглушення через темність, не "
                        "знесичення (той самий ремонт, що K-KOH-08)",
                        "АБО зменшити площу цього кольору до аксесуара"],
                запит=dict(слот=e.get("слот"), цільова_L=[5.0, 45.0], цільова_C=[0.0, 45.0],
                           чому="тихіша версія під мету «приховати»"),
                ламається="мета — напрям, не вето: її явний вибір цієї речі знімає знахідку "
                          "(п.9); поріг калібрований на нагоді, де питання те саме (K-KOH-08)",
                поріг=ст, вимір=г),
                сила_нп=сила_нп,
                сила_нп_джерело="вимір (гучність C*×L* над стелею × площа)"))
        for e in (E or []):
            r = за_ід.get(e.get("річ")) or {}
            if not r or її_вибір(r):
                continue
            свідки, _в = свідки_помітності(r, тіло)
            інші = [с for с in свідки if not с.startswith("гучність")]
            if not інші:
                continue
            зн.append(dict(_РЕЄСТР._зн(
                "R-CHEV-08", "hint",
                "річ помітна не кольором, а собою, а мета образу — приховати", [e.get("річ")],
                "%s; мета зі слів жінки — «приховати» (тема-6 §1.6)" % "; ".join(інші),
                ремонт=["та сама річ без оздоби, без блиску або закритіша"],
                ламається="свідки грубі: `outfit.зони_речі` не бачить глибини вирізу, "
                          "`свідки_блиску` — блиску без слова крамниці й без фото. Її явний "
                          "вибір знімає знахідку (п.9)"),
                сила_нп=0.25,
                сила_нп_джерело="свідок словом крамниці — числа під ним нема"))
    elif not гучні and any(e.get("C") is not None for e in (E or [])):
        найбільша = max((e for e in E if e.get("C") is not None),
                        key=lambda e: (e.get("площа") or 0))
        зн.append(dict(_РЕЄСТР._зн(
            "R-CHEV-08", "hint",
            "увагу не тримає ніщо, а мета образу — експресія", [найбільша.get("річ")],
            "жодна річ образу не дістає стелі гучності %.0f (C* × L*/50); мета зі слів жінки "
            "про цей вихід — «експресія» (тема-6 §1.6: вісь уваги міняє НАПРЯМ поради)" % ст,
            ремонт=["гучніший колір в одному слоті — акцент, не весь образ",
                    "АБО річ, помітна собою: оздоба, блиск, відкритіший крій"],
            ламається="мета — напрям, не вимога: тихий образ на «експресію» не блокується, і "
                      "образ із невиміряним кольором знахідки не дістає взагалі"),
            сила_нп=0.25,
            сила_нп_джерело="вимір є (гучність усіх речей), порога «скільки треба» корпус не дає"))
    return зн
