# -*- coding: utf-8 -*-
"""портрет_вимір.py — її кольори з портрета міряє код: шкіра, волосся, очі — з розкидом і кадром.

ЧОМУ (корінь Річ-ознаки-обличчя, крок «код міряє портрет сам»). Hex моделі зору — оцінка (`model_hex`): її розкиду
ніхто не міряв, і правила, що стоять на рисах обличчя (контраст, глибина, очі, сивина), з нею мовчать. Тепер модель
зору лише показує, ДЕ зони — рамки в тисячних кадру, та сама умова, що рамка речі (`річ_з_фото.рамка_з_тисячних`), —
а колір міряє код з пікселів портрета, як колір речі (`аудит/ПРОДУКТ.md` п.18): показ ріже кожну зону з портрета
(`кадрЗониП`, ≤64 px на бік), тут — Lab, відкид клипованих пікселів, блиску й тіні (`extract`), медіана, похибка
оцінки (бутстреп медіани) і шум зон.

ВОРОТА КАДРУ (R-PC-10, тема 2). Контраст обличчя — відношення: спільний зсув експозиції його не псує, а незалежний
шум зон губить; «ворота мусять відкидати спрямоване світло, а не виправляти його». Шум зон — різниця двох щік
(симетричні ділянки однієї поверхні): понад `ШУМ_ЗОН_МЕЖА` — портрет поза воротами (`portrait_uneven_light`), і
профіль лишається оцінкою моделі під власним ім'ям; менший шум іде в `se_L` шкіри, і довіра контрасту падає за
`надійність_контрасту`. Зона, де після фільтрів замало пікселів, — теж поза воротами, своїм кодом: жінці сказано,
який портрет надіслати. Повтор виміру того самого кадру дає те саме: вибірки бутстрепа — з фіксованим сідом.
"""
import base64 as _b64
import math
import random
import re
import statistics as _st
from колір_простір_перетворення import to_lab, to_rgb, lch
from extract import reject_specular, reject_shadow, СІД

# вхід мосту з показу: міст_вхід (`вимір_портрета`) читає ключ `портрет_вимір` — оголошення тут, при модулі
# виміру: у міст_вхід ім'я `ЗОВНІШНІ_ВХОДИ` затуляло б `bridge.ЗОВНІШНІ_ВХОДИ` (з міст_пакет) для проби поділу
ЗОВНІШНІ_ВХОДИ = {
    "портрет_вимір": "вхід із показу (`КОЛІР.вимір` у будівниках входу): вимір кадру портрета кодом "
                     "(`портрет_вимір.виміряти`) — лише коли ворота пройдено; є — риси беруться з нього (`вимір_портрета`)",
}
ДЖЕРЕЛО = "uncontrolled"   # фото без протоколу зйомки: довіра осей — `AXIS_RELIABILITY["uncontrolled"]`
СТОРОНА_ЗОНИ = 64          # px на бік кадру зони, який ріже показ (`кадрЗониП`)
# Ключі рамок у відповіді моделі (`міст_вхід.ЧИТАННЯ_ПОРТРЕТА`) → ім'я зони тут
ЗОНИ = {"cheek_left": "щока_ліва", "cheek_right": "щока_права", "forehead": "лоб", "hair": "волосся",
        "iris_left": "око_ліве", "iris_right": "око_праве"}
ЩОКИ = ("щока_ліва", "щока_права")
ШКІРА = ЩОКИ + ("лоб",)
ОЧІ = ("око_ліве", "око_праве")
ПРИЧИНИ_ВИМІРУ = ("portrait_uneven_light", "portrait_skin_unmeasured", "portrait_hair_unmeasured",
                  "portrait_eyes_unmeasured")
# T3, R-PC-10 (реєстр `contrast_noise`): незалежний шум 4 L* на зону — 127 % міжособового розкиду контрасту,
# «directional light across the face is fatal»; на цій межі `надійність_контрасту` уже нуль
ШУМ_ЗОН_МЕЖА = 4.0
МІН_ПІКСЕЛІВ = {"шкіра": 40, "волосся": 40, "очі": 12}   # T3: менше — число, але не вимір (як `MIN_SCLERA_PX`)
КЛИП = (6, 249)            # канал на межі сенсора (0/255 після стиснення) — колір зрізано, не виміряно
КІЛЬЦЕ_РАЙДУЖКИ = (0.35, 0.95)   # частка радіуса рамки райдужки: без зіниці в центрі й повіки по краю
БУТСТРЕП = 16
# ПЕВНІСТЬ КЛАСІВ. Другий знімок тієї самої жінки — інша автоекспозиція й інший автобаланс білого: спільний зсув
# усіх рис (R-PC-10: контраст-відношення його витримує, абсолютна світлота й тон — ні), і своя похибка кожної
# зони. Клас, що змінюється між варіантами, — «не певна» (`face_features.певно`).
ЗСУВ_ЗЙОМКИ = 0.10   # T3: ±10 % лінійної яскравості й каналів R, B між двома селфі за автоматики смартфона
Z_ПЕВНОСТІ = 2.0     # T3: ±2 похибки оцінки (se) кожної риси


def розпакувати(кадр):
    """{дані: base64url RGB рядок за рядком, ширина, висота} → (w, h, [(r, g, b)…]); не той вхід — ValueError."""
    w, h = int(кадр["ширина"]), int(кадр["висота"])
    с = str(кадр["дані"])
    сирі = _b64.urlsafe_b64decode(с + "=" * (-len(с) % 4))
    if w <= 0 or h <= 0 or len(сирі) != w * h * 3:
        raise ValueError("кадр зони: %d байт на %d×%d" % (len(сирі), w, h))
    return w, h, [tuple(сирі[i:i + 3]) for i in range(0, len(сирі), 3)]


def _lab_кадру(кадр, кільце=None):
    """Lab пікселів кадру без клипованих; `кільце` (r0, r1) — лише пікселі еліпса рамки між r0 і r1 радіуса."""
    w, h, пкс = розпакувати(кадр)
    вих = []
    for i, p in enumerate(пкс):
        if кільце:
            x, y = i % w, i // w
            r = math.hypot((x + 0.5 - w / 2) / (w / 2), (y + 0.5 - h / 2) / (h / 2))
            if not (кільце[0] <= r <= кільце[1]):
                continue
        if max(p) > КЛИП[1] or min(p) < КЛИП[0]:
            continue
        вих.append(to_lab(p))
    return вих


def _медіана(labs):
    return tuple(_st.median(l[i] for l in labs) for i in range(3))


def _похибка(labs):
    """Похибка оцінки медіани (бутстреп, сід фіксований): (se_L, se_ab) — не розкид пікселів."""
    if len(labs) < 2:
        return None, None
    р = random.Random(СІД)
    оц = [_медіана([labs[р.randrange(len(labs))] for _ in labs]) for _ in range(БУТСТРЕП)]
    sd = [_st.pstdev(o[i] for o in оц) for i in range(3)]
    return round(sd[0], 2), round(max(sd[1], sd[2]), 2)


def _зона(labs, риса, шкіра=None):
    """Пікселі зони → dict(lab, n, se_L, se_ab, розкид_L, придатна) після відкиду блиску й тіні; None — пікселів нема.
    `придатна` — пікселів не менше за `МІН_ПІКСЕЛІВ[риса]`: менше — число, але не вимір (точка несе свою придатність,
    паспорт Річ-колір-вимір, п.1). `шкіра` — Lab шкіри: у рамці райдужки повіка й склера відкидаються (ΔE до шкіри < 8;
    світліше за шкіру й сіре)."""
    if шкіра is not None:
        labs = [l for l in labs if math.dist(l, шкіра) >= 8.0 and not (l[0] > шкіра[0] + 5 and lch(l)[1] < 6)]
    labs, _ = reject_specular(labs)
    labs, _ = reject_shadow(labs)
    if not labs:
        return None
    Ls = sorted(l[0] for l in labs)
    se_L, se_ab = _похибка(labs)
    return dict(lab=[round(v, 2) for v in _медіана(labs)], n=len(labs), se_L=se_L, se_ab=se_ab,
                розкид_L=round(Ls[int(0.9 * (len(Ls) - 1))] - Ls[int(0.1 * (len(Ls) - 1))], 1),
                придатна=len(labs) >= МІН_ПІКСЕЛІВ[риса])


def виміряти(кадри):
    """{ім'я зони: кадр пікселів} (імена — `ЗОНИ.values()`) → запис виміру.

    `стан` «вимір» — ворота пройдено: шкіра (медіана ділянок, `точки` — кожна ділянка, `шум_зон` — щока проти щоки,
    `se_L` з ним), волосся, очі (обидві райдужки разом), `джерело` «uncontrolled». «поза_воротами» — `причини` кодами
    `ПРИЧИНИ_ВИМІРУ`: кольорів профілю з такого виміру нема, лишається оцінка моделі."""
    кадри = кадри or {}
    причини, зони = [], {}
    for ім in ШКІРА:
        if кадри.get(ім):
            з = _зона(_lab_кадру(кадри[ім]), "шкіра")
            if з and з["придатна"]:
                зони[ім] = з
    щоки = [зони[ім] for ім in ЩОКИ if ім in зони]
    шкіра = шум = None
    if len(щоки) < 2:
        причини.append("portrait_skin_unmeasured")
    else:
        шум = round(abs(щоки[0]["lab"][0] - щоки[1]["lab"][0]) / math.sqrt(2), 2)
        if шум > ШУМ_ЗОН_МЕЖА:
            причини.append("portrait_uneven_light")
        точки = [зони[ім]["lab"] for ім in ШКІРА if ім in зони]
        se = max(зони[ім]["se_L"] or 0.0 for ім in ШКІРА if ім in зони)
        шкіра = dict(lab=[round(v, 2) for v in _медіана(точки)], точки=точки, шум_зон=шум,
                     se_L=round(math.hypot(se, шум), 2),
                     se_ab=max(зони[ім]["se_ab"] or 0.0 for ім in ШКІРА if ім in зони),
                     n=sum(зони[ім]["n"] for ім in ШКІРА if ім in зони))
    волосся = _зона(_lab_кадру(кадри["волосся"]), "волосся") if кадри.get("волосся") else None
    if not волосся or not волосся["придатна"]:
        причини.append("portrait_hair_unmeasured")
        волосся = None
    очі = None
    if шкіра:
        окремо = {ім: _lab_кадру(кадри[ім], КІЛЬЦЕ_РАЙДУЖКИ) for ім in ОЧІ if кадри.get(ім)}
        очі = _зона([l for ім in ОЧІ for l in окремо.get(ім, [])], "очі", tuple(шкіра["lab"]))
        поокремо = [з for з in (_зона(окремо[ім], "очі", tuple(шкіра["lab"])) for ім in окремо) if з]
        if очі and len(поокремо) == 2:
            # дві райдужки — два заміри однієї величини: їхня різниця — шум зон, як щока проти щоки
            різн = [abs(поокремо[0]["lab"][i] - поокремо[1]["lab"][i]) / math.sqrt(2) for i in range(3)]
            очі.update(шум_зон=round(різн[0], 2), se_L=round(math.hypot(очі["se_L"] or 0.0, різн[0]), 2),
                       se_ab=round(math.hypot(очі["se_ab"] or 0.0, max(різн[1], різн[2])), 2))
    if not очі or not очі["придатна"]:
        причини.append("portrait_eyes_unmeasured")
        очі = None
    return dict(стан="поза_воротами" if причини else "вимір", причини=причини, джерело=ДЖЕРЕЛО,
                шкіра=шкіра, волосся=волосся, очі=очі,
                зони={ім: dict(n=з["n"], lab=з["lab"]) for ім, з in зони.items()}, межа_шуму=ШУМ_ЗОН_МЕЖА)


def рамка_зони(v):
    """Рамка зони з відповіді моделі ({left, top, right, bottom}, [л, в, п, н] чи ті самі чотири числа одним рядком,
    у тисячних) → dict або None. Та сама умова, що рамка речі (`річ_з_фото.рамка_з_тисячних`), без нижньої межі 2 %:
    райдужка мала."""
    if isinstance(v, (list, tuple)) and len(v) == 1:
        v = v[0]
    if isinstance(v, str):
        v = re.findall(r"-?\d+(?:\.\d+)?", v)
    if isinstance(v, (list, tuple)) and len(v) == 4:
        v = dict(left=v[0], top=v[1], right=v[2], bottom=v[3])
    if not isinstance(v, dict):
        return None
    # число чи рядок числа — інакше рамки нема (зона лишається невиміряною і йде в причини виміру), без перехоплення
    # винятку: ваду коду воно сховало б як брак рамки
    чотири = [v.get(k) for k in ("left", "top", "right", "bottom")]
    чотири = [float(x) if isinstance(x, (int, float)) and not isinstance(x, bool)
              else float(x) if isinstance(x, str) and re.fullmatch(r"\s*-?\d+(?:\.\d+)?\s*", x) else None for x in чотири]
    if None in чотири:
        return None
    л, в_, п, н = чотири
    л, п = sorted((max(0.0, min(1000.0, л)), max(0.0, min(1000.0, п))))
    в_, н = sorted((max(0.0, min(1000.0, в_)), max(0.0, min(1000.0, н))))
    if п - л < 5 or н - в_ < 5:
        return None
    return dict(ліво=round(л), верх=round(в_), право=round(п), низ=round(н))


def рамки(zones):
    """Поле `zones` відповіді моделі → {ім'я зони: рамка} (лише придатні); не dict — порожньо."""
    if not isinstance(zones, dict):
        return {}
    return {ЗОНИ[к]: р for к, v in zones.items() if к in ЗОНИ and (р := рамка_зони(v))}


def _лін(c):
    return ((c + .055) / 1.055) ** 2.4 if c > .04045 else c / 12.92


def _гам(c):
    return 1.055 * c ** (1 / 2.4) - .055 if c > .0031308 else 12.92 * c


def _зйомка(lab, множники):
    """Lab під іншою зйомкою: лінійні R, G, B кадру помножено на `множники` (експозиція — всі три, баланс — один)."""
    lin = [_лін(c) * k for c, k in zip(to_rgb(*lab), множники)]
    return to_lab([_гам(c) * 255 for c in lin])


def варіанти(риси):
    """{риса: (lab, se_L, se_ab)} → [{риса: lab}]: сам кадр; спільні зсуви зйомки (експозиція, R, B ±`ЗСУВ_ЗЙОМКИ`);
    крайні похибки оцінки: L кожної риси ±Z·se_L за всіма поєднаннями знаків, a/b — ±Z·se_ab уздовж хроми й поперек."""
    к = ЗСУВ_ЗЙОМКИ
    вих = [{р: tuple(в[0]) for р, в in риси.items()}]
    for м in ((1 - к,) * 3, (1 + к,) * 3, (1 - к, 1, 1), (1 + к, 1, 1), (1, 1, 1 - к), (1, 1, 1 + к)):
        вих.append({р: _зйомка(в[0], м) for р, в in риси.items()})
    імена = sorted(риси)
    for маска in range(2 ** len(імена)):
        вих.append({р: (риси[р][0][0] + (1 if маска >> i & 1 else -1) * Z_ПЕВНОСТІ * (риси[р][1] or 0.0),
                        риси[р][0][1], риси[р][0][2]) for i, р in enumerate(імена)})
    for вздовж, знак in ((True, 1), (True, -1), (False, 1), (False, -1)):
        варіант = {}
        for р, (lab, _, se_ab) in риси.items():
            L, a, b = lab
            C = lch(lab)[1] or 1.0
            ua, ub = (a / C, b / C) if вздовж else (-b / C, a / C)
            д = знак * Z_ПЕВНОСТІ * (se_ab or 0.0)
            варіант[р] = (L, a + д * ua, b + д * ub)
        вих.append(варіант)
    return вих


def розкид_b(риси, риса):
    """Похибка b* риси з того самого кадру: найбільший відхід b* серед `варіанти(риси)` — спільний зсув зйомки
    й крайня похибка оцінки. Її читає бік очей (R-COL-16): бік названо, лише коли весь інтервал b* ± розкид — за межею."""
    b0 = риси[риса][0][2]
    return max(abs(в[риса][2] - b0) for в in варіанти(риси))


def певні(риси, класи):
    """Які класи тримає кадр: `класи({риса: lab})` → {клас: значення}; певний — однаковий у всіх `варіанти(риси)`."""
    усі = [класи(в) for в in варіанти(риси)]
    return {к: all(кл[к] == усі[0][к] for кл in усі) for к in усі[0]}
