def причина(відкинуто):
    """Причини відмов → один рядок повтору «код: номери; …» (порядок — перша поява)."""
    за_кодом = {}
    for в in відкинуто:
        про = в.get("про")
        за_кодом.setdefault(в["чому"], [])
        if isinstance(про, list):
            за_кодом[в["чому"]] += [str(x) for x in про if str(x) not in за_кодом[в["чому"]]]
    return "; ".join(к + (": " + ", ".join(в) if в else "") for к, в in за_кодом.items())


def пояснити_повтор(промпт, причина_рядком, маркер):
    """Промпт повтору: перед `маркер` — розбіжність попередньої відповіді словами межі."""
    if not причина_рядком:
        return промпт
    слова = []
    for шматок in str(причина_рядком).split("; "):
        код, _, про = шматок.partition(": ")
        шаблон = _ЧОМУ.get(код, код)
        слова.append(шаблон % про if "%s" in шаблон else шаблон)
    return промпт.replace(маркер, "Розбіжність попередньої відповіді: " + "; ".join(слова)
                          + ". Це єдиний повтор.\n\n" + маркер, 1)
