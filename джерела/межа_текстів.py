            "text — що відомо і що з цим робити; unknown — чого ти не знаєш (вона бачить це за кнопкою «Чого я не "
            "знаю»): що саме невідомо і, коли цей чи інший факт про ту саму річ це називає, що вона може зробити, "
            "щоб це стало відомо. Речення про те, чого ти не знаєш, не можеш сказати чи не перевірила, — лише в "
