class ІдУТілі(Exception):
    """Тіло запиту несе ід реєстру чи його домен: це `Збій`, а не виклик."""

    def __init__(self, збій):
        super().__init__("%s: %s" % (збій.вид, збій.що))
        self.збій = збій


def _домен(ід):
    """Домен ід крамниці («ж-1@shop.ua» → «shop.ua»); ід без «@» домену не має."""
    _, знак, дім = str(ід).rpartition("@")
    return дім.strip().lower() if знак and "." in дім else None


def номерами(значення, номери):
    """Те саме значення, де кожен рядок, що дорівнює ід із `номери` ({ід: номер}), — у ключах і в значеннях, —
    номер, а рядок, що дорівнює домену такого ід, вилучено. Назви поля не читає: ід — те, що в реєстрі."""
    домени = {д for д in map(_домен, номери) if д}

    def домен(x):
        return isinstance(x, str) and x.strip().lower() in домени

    def н(x):
        if isinstance(x, dict):
            return {(номери.get(к, к) if isinstance(к, str) else к): н(в) for к, в in x.items() if not домен(в)}
        if isinstance(x, (list, tuple)):
            return [н(в) for в in x if not домен(в)]
        if isinstance(x, str):
            return номери.get(x, x)
        return x
    return н(значення)


def перевірити_тіло(тіло, номери, частина="межа_текстів"):
    """Тіло запиту до моделі не несе жодного ід реєстру й жодного його домену; несе — `ІдУТілі` зі `Збій`."""
    т = str(тіло).lower()
    знайдено = [і for і in номери if str(і).lower() in т]
    знайдено += [д for д in sorted({д for д in map(_домен, номери) if д}) if д in т]
    if знайдено:
        raise ІдУТілі(Збій("id_in_body", частина, "тіло", що=", ".join(знайдено[:5])))
    return тіло


class Межа:
    """Факти одного виклику: номери одного роду, стани, реєстр ід. Писач тексту додає факти, межа нумерує їх,
    будує вхід моделі, звіряє тіло й судить відповідь."""

    def __init__(self, *, лише_невідоме=None, з_порадами=False, без_адрес_пулу=False):
        self.факти = {}            # номер → {"state": стан, …зміст}
        self.реєстр = {}           # ід → номер речі
        self.адреси_речей = {}      # адреса рядка пулу → номер речі цього складу
        self._групи = {}           # ключ змісту → номер (одна заява про кілька речей — один факт)
        self.мусить_у_тексті = []  # номери, які мусить назвати основний текст (її власна річ)
        self.лише_невідоме = лише_невідоме
        self.без_адрес_пулу = без_адрес_пулу
        self.розділи = ("text", "advice", "unknown") if з_порадами else ("text", "unknown")

    def _новий(self, стан, зміст):
        н = "f%d" % (len(self.факти) + 1)
        self.факти[н] = dict({"state": стан}, **{к: в for к, в in (зміст or {}).items()
                                                 if в not in (None, "", [], {})})
        return н

    def предмет(self, ід=None, **зміст):
        """Річ як факт (`item`); той самий ід — той самий номер, зміст доповнюється."""
        ід = str(ід) if ід not in (None, "") else None
        if ід and ід in self.реєстр:
            н = self.реєстр[ід]
            for к, в in зміст.items():
                if в not in (None, "", [], {}):
                    self.факти[н].setdefault(к, в)
            return н
        н = self._новий(ПРЕДМЕТ, зміст)
        if ід:
            self.реєстр[ід] = н
        return н

    def зареєструвати(self, ідс):
        """Ід, яких ще нема в реєстрі, — речами без опису (їх називає заява, а не перелік)."""
        return [self.предмет(і) for і in ідс if і not in (None, "")]

    def факт(self, стан, зміст=None, предмети=()):
        """Факт зі станом. Той самий стан і зміст про різні речі — один факт із переліком `items`."""
        зміст = номерами(зміст or {}, self.реєстр)
        предмети = list(dict.fromkeys(предмети))
        ключ = _json.dumps([стан, зміст], ensure_ascii=False, sort_keys=True)
        if предмети and ключ in self._групи:
            н = self._групи[ключ]
            self.факти[н]["items"] = list(dict.fromkeys(self.факти[н]["items"] + предмети))
            return н
        н = self._новий(стан, dict(dict(items=предмети) if предмети else {}, **зміст))
        if предмети:
            self._групи[ключ] = н
        return н

    def заява(self, з, предмети=()):
        """Заява коду → факт зі станом-кодом заяви; її речі — номерами (`item_ids` у реєстрі)."""
        речі = self.зареєструвати(з.get("item_ids") or ()) or list(предмети)
        зміст = dict(values=з.get("values") or {})
        for к in ("choice", "source"):
            if з.get(к) not in (None, "unknown"):
                зміст[к] = з[к]
        if з.get("rank") is not None:
            зміст["rank"] = з["rank"]
        if з.get("part") is not None:
            зміст["part"] = з["part"]
        return self.факт(str(з.get("code")), зміст, речі)

    def причини(self, н, номери):
        """Факт `н` стверджується лише разом із причиною: `because` — номери фактів, з яких він випливає (вердикт
        речі — з решти заяв того самого вердикту). Речення, що називає `н` без жодної з них, межа не показує
        (`reason_missing`): «не можу сказати, чи пасує» без «бо колір невідомий — назви його» — «не знаю» без дії."""
        номери = [і for і in номери if і != н and і in self.факти]
        if номери:
            self.факти[н]["because"] = list(dict.fromkeys((self.факти[н].get("because") or []) + номери))

    def питати_її(self, н):
        """Факт `н` — те, що дасть лише її відповідь (`ask_her`): про нього можна одне питання останнім реченням
        text, і кажуть його одним реченням, навіть коли він про кілька речей (шість «ти його не згадала» по одній
        на річ у кадрі — одне речення з питанням; доповнення менеджера 26.11, (б))."""
        self.факти[н]["ask_her"] = True

    # ── ВХІД МОДЕЛІ ──
    def вхід(self):
        """Факти для промпту: {номер: факт}, ід — номерами (`номерами` за реєстром)."""
        return номерами(self.факти, {**self.реєстр, **self.адреси_речей})

