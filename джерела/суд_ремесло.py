def оголосити_фокус_свідомим(знахідки, свідомі, intent="conventional"):
    """Знахідки, де K-CRA-02 перебудовано за свідомими ходами стилістки.

    Свідомий хід (`розбір_відповідей._застосувати_свідомі`: адресати — id, назви,
    слоти) над річчю однієї з груп фокусів робить цю групу ОГОЛОШЕНОЮ ("deliberate"):
    K-CRA-02 каже «the focus is chosen deliberately», і вибір стилістки — її
    зважене рішення (CLAUDE.md п.17). Тоді вона йде в `keep` поруч з акцентом схеми,
    який не стишується й так; стишити лишаються тільки неоголошені групи. Коли
    оголошено всі — ремонту нема, лишається лічба як інформація (сила вже знижена
    свідомим ходом ×0.6). Сила, `свідомий` та інші поля знахідки — як були."""
    адр = {str(a) for р in (свідомі or []) if isinstance(р, dict) and not р.get("без_адресата")
           for a in (р.get("адресати") or [])}
    if not адр:
        return знахідки
    вих = []
    for z in знахідки:
        гр = z.get("групи_фокусів") if z.get("правило") == "K-CRA-02" else None
        if гр and any(not g.get("оголошено") and адр & {str(x) for x in g["речі"] + g["слоти"]}
                      for g in гр):
            гр = [dict(g, оголошено="deliberate")
                  if not g.get("оголошено") and адр & {str(x) for x in g["речі"] + g["слоти"]}
                  else g for g in гр]
            нова = фокуси_знахідка(гр, intent)
            z = dict(z, групи_фокусів=гр, заяви=нова.get("заяви"),
                     **{к: нова.get(к) for к in ("ремонт", "ремонт_заяви", "чому")})
            z = {к: v for к, v in z.items() if v is not None}
        вих.append(z)
    return вих


def жести(команди):
    """[знахідки] K-CRA-03: щонайбільше один жест sprezzatura.

    ВХІД — КОМАНДИ РОЗКЛАДКИ, і це не натяжка, а те, що K-CRA-11 прямо каже:
    «образ — це набір речей ПЛЮС набір команд». Розстебнути, накинути, підняти
    комір, зав'язати пояс вузлом — рівно той перелік, який K-CRA-03 зве вивченою
    недбалістю («a rolled cuff, a half-tuck, an undone button, pushed sleeves»).
    Доти пункт 10 чекліста питав поле `жест`, якого не пише НІХТО, тож стояв у
    стані «без входу» на кожному образі.

    Сила — `hint`: корпус дає `strong` самому ПОНЯТТЮ і `hint` стелі в одиницю
    («The one-gesture limit is ours and belongs in the invented-number list»)."""
    ж = [z for z in (команди or [])
         if isinstance(z, dict) and z.get("правило") and _жест(z)]
    if len(ж) <= 1:
        return []
    return [dict(_зн(
        "K-CRA-03", "hint",
        "жестів sprezzatura %d — два вже читаються неохайністю, не свободою" % len(ж),
        sorted({r for z in ж for r in (z.get("речі") or [])}),
        "команди розкладки цього образу: %s. Вивчена недбалість працює, поки вона "
        "ОДНА: другий жест знімає з першого ознаку вибору"
        % "; ".join("%s («%s»)" % (z["правило"], str(z.get("суть") or "")[:38]) for z in ж),
        ремонт=["лишити один жест — той, що ближче до обличчя; решту виконати рівно "
                "(застебнути, опустити комір, надіти як належить)"],
        заяви=[_ВМ.заява("sprezzatura_gestures_over_one", count=len(ж))],
        ремонт_заяви=[_ВМ.заява("keep_one_gesture_near_face")],
        ламається="Castiglione (1528) підтримує ПОНЯТТЯ і нічого більше: ні речей, "
                  "ні підкотів, ні стелі в одиницю. Саме число «один» — наше, і "
                  "корпус тримає його в списку вигаданих",
        поріг=1.0, вимір=float(len(ж)), повна=2.0))]


# Команди, які Є жестом вивченої недбалості, і команди, які ним НЕ є. Список
# іменний, не за словами в тексті: слово не знає, чиє воно (той самий урок, що в
# `status.ВИМКНЕНІ_ПРАВИЛА` — регекс по тексту вбив чуже правило).
ЖЕСТИ_ID = ("K-OUT-11",     # розстебнути / лишити відкритим
            "K-OUT-19",     # пояс завʼязується вузлом, а не застібається
            "K-OUT-29",     # підняти комір
            "K-OUT-32",     # накинути на плечі
            "K-OUT-34")     # стан «накинуто»


def _жест(z):
    """Чи команда `z` — жест вивченої недбалості: її правило стоїть у ЖЕСТИ_ID
    (іменний список, не пошук за словами — див. коментар над ним)."""
    return str(z.get("правило")) in ЖЕСТИ_ID


def глибина_шарів(речі, E):
    """[знахідки] K-CRA-06: у шаруванні є правила глибини.

    ДВІ ПОЛОВИНИ ПРАВИЛА, І ВОНИ З РІЗНИМ ВХОДОМ.
      · СТЕЛЯ ВИДИМИХ ШАРІВ (3, `[folkloric constant]`) — вхід є завжди (слоти);
      · ГРАДАЦІЯ ДОВЖИН («видимий крок між шарами») — вхід є рівно тоді, коли
        обидва шари несуть рівень довжини. Виміряно на `каталог_повний`:
        `довжина_рівень` мають 534 із 3 121 «верх» (17 %) і 209 із 764
        «верхній_шар» (27 %), тобто пара з обома рівнями трапляється, але рідко.
        Без рівня правило МОВЧИТЬ — довжина не вигадується.
    Третьої половини (градація товщини, «тонке під товстим») тут нема, і це
    названо: товщини виробу фід не несе ЖОДНИМ полем, а виводити її з родини
    матеріалу — та сама вигадка, від якої відмовився шар реєстрів («футболка ·
    вовна» 353 рази в цьому ж каталозі)."""
    зн = []
    видимі = [e for e in одна_на_річ(E) if e.get("слот") in ШАРОВІ_СЛОТИ]
    if len(видимі) > СТЕЛЯ_ШАРІВ:
        зн.append(dict(_зн(
            "K-CRA-06", "default",
            "видимих шарів %d при стелі %d" % (len(видимі), СТЕЛЯ_ШАРІВ),
            [e.get("річ") for e in видимі],
            "практична стеля шарування — три видимі шари; далі силует перестає "
            "читатись як рішення",
            ремонт=["зняти один шар — той, що не несе ні тепла, ні кольору"],
            заяви=[_ВМ.заява("visible_layers_over_ceiling", count=len(видимі), ceiling=СТЕЛЯ_ШАРІВ)],
            ремонт_заяви=[_ВМ.заява("remove_layer_without_warmth_or_colour")],
            ламається="число 3 — `[folkloric constant]`, так його називає сам корпус",
            поріг=float(СТЕЛЯ_ШАРІВ), вимір=float(len(видимі)), повна=2.0)))
    # ── ГРАДАЦІЯ ДОВЖИН: КРОК МІЖ ШАРАМИ МУСИТЬ БУТИ ВИДИМИЙ ────────────────
    рівні = {}
    for r in речі:
        if r.get("слот") in ("верх", "верхній_шар") and r.get("довжина_рівень"):
            рівні.setdefault(str(r["довжина_рівень"]).strip().lower(), []).append(r)
    збіг = [(рів, шари) for рів, шари in рівні.items() if len(шари) > 1]
    for рів, шари in збіг:
        зн.append(dict(_зн(
            "K-CRA-06", "default",
            "два шари завершуються на одному рівні («%s») — кроку між ними нема" % рів,
            шари,
            чому="градація довжин: між шарами мусить бути ВИДИМИЙ крок. Два поділи на "
            "одному рівні читаються як одна товста горизонталь, а не як два шари",
            ремонт=["взяти верхній шар помітно довшим або коротшим за те, що під ним"],
            заяви=[_ВМ.заява("layers_end_at_same_level", level={"максі": "ankle", "литка": "calf",
                                                                "коліно": "knee", "стегно": "hips",
                                                                "талія": "waist"}.get(рів, _ВМ.UNKNOWN))],
            ремонт_заяви=[_ВМ.заява("outer_layer_clearly_longer_or_shorter")],
            ламається="рівень довжини — СЛОВО картки («міді», «кроп»), а не сантиметри: "
                      "дві речі одного рівня можуть різнитись на кілька сантиметрів, і "
                      "це вже видимий крок. Тому знахідка називає рівень, а не відстань",
            поріг=1.0, вимір=float(len(шари)), повна=2.0)))
    return зн


def камера_проти_життя(E):
    """[знахідки] K-CRA-10: камера ≠ життя, і наш власний рендер — фотографія.

    ЩО САМЕ ТУТ СТВЕРДЖУЄТЬСЯ. Не «образ поганий». Стверджується рівно те, що
    корпус називає зміщенням ВЛАСНОГО каналу: фактурний контраст на фотографії
    майже зникає, а приміряння людина бачить саме рендером. Отже образ, чий
    інтерес тримається ЛИШЕ на фактурі, у рендері виглядатиме порожнішим, ніж він
    є, — і жінка судитиме його по картинці.

    Сила `hint` — так дає корпус. Умова однобічна: ні хроми, ні принту, сама
    фактура. Коли інтерес несе колір або принт, зміщення каналу знахідки не варте:
    фотографія передає і те, і те."""
    дж = джерела_інтересу(E)
    if not дж:
        return []                          # порожнечу вже називає K-INT-04
    лише_фактура = [d for d in дж if all(в.startswith("фактура") for в in d["важелі"])]
    if len(лише_фактура) != len(дж):
        return []
    return [dict(_зн(
        "K-CRA-10", "hint",
        "увесь інтерес образу — фактурний, а рендер приміряння це з'їдає",
        [d["річ"] for d in лише_фактура],
        "джерел інтересу %d, і всі до одного фактурні (%s). Фотографія просить "
        "більше контрасту, більше структури й гострішого силуету; фактурний "
        "контраст на ній зникає майже цілком — а наш рендер і Є фотографія"
        % (len(дж), "; ".join(", ".join(d["важелі"]) for d in лише_фактура[:3])),
        ремонт=["для рендера — додати одне НЕфактурне джерело: акцентний колір або "
                "чіткіший край силуету; у житті образ працює як є"],
        заяви=[_ВМ.заява("interest_only_texture_render_loses", sources=len(лише_фактура))],
        ремонт_заяви=[_ВМ.заява("add_non_texture_source_for_render")],
        ламається="це зміщення НАШОГО каналу, не вада образу: правило знає лише "
                  "напрям («фактура на фото слабшає»), а не величину — окремого "
                  "режиму оцінки «для камери» в системі нема",
        поріг=0.0, вимір=float(len(лише_фактура)), повна=2.0))]


def ремесло(речі, E, команди=(), intent="conventional", спец=None, фокус=None):
    """Сім'я K-CRA над зібраним образом: (знахідки). Один вхід — один викликач.

    `команди` — команди розкладки цього образу (`outer.команди_укладки` +
    `outer.ремонти`): вхід K-CRA-03. Порожньо — правило мовчить, як і має.
    `спец` (специфікація палітри: ролі слотів) і `фокус` (фокусна зона сценарію) —
    вхід K-CRA-02: чим оголошено фокус (ФОКУС-1)."""
    зн = (третя_річ(речі) + фокуси(E, intent, спец, фокус) + жести(команди)
          + глибина_шарів(речі, E) + камера_проти_життя(E))
    return [z for z in обмежити_вагу(зн) if not z.pop("під_підлогою", False)]
