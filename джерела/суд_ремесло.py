def третя_річ(речі):
    """[знахідки] K-CRA-01: верх+низ (або сукня) без шару й без аксесуара — «одягнена»,
    не «стилізована».

    ЧОМУ ЗІ `речі`, А НЕ З `E`: `елементи()` у стані «у_приміщенні» ВИКИДАЄ верхній
    шар, тобто образ із пальтом читався б тут як образ без третьої речі. Це той
    самий клас, що й лічба теплових шарів у `погода()`: третя річ — не питання
    видимості в одному зі станів."""
    слоти = [r.get("слот") for r in речі]
    if not any(с in БАЗОВІ_СЛОТИ for с in слоти):
        return []                                  # це не образ — про це каже структура
    треті = [r for r in речі if r.get("слот") in ТРЕТЯ_РІЧ_СЛОТИ]
    if треті:
        return []
    return [dict(_зн(
        "K-CRA-01", "strong",
        "третьої речі нема: %d позиц(ії) бази й жодного шару чи аксесуара" % len(речі),
        list(речі),
        "верх+низ (або сукня) — це «одягнена». «Стилізована» починається з ТРЕТЬОГО "
        "елемента: шар (жакет, кардиган, жилет) або сильний аксесуар (пояс, шарф, "
        "прикраса). У цьому образі слоти: %s" % ", ".join(sorted(set(с for с in слоти if с))),
        ремонт=["додати один шар — жакет, кардиган або жилет",
                "АБО один сильний аксесуар — пояс, шарф, виразну прикрасу"],
        заяви=[_ВМ.заява("no_third_piece_dressed_not_styled", items=len(речі))],
        ремонт_заяви=[_ВМ.заява("add_layer_or_strong_accessory")],
        запит=dict(слот="верхній_шар", чому="K-CRA-01: третя річ"),
        ламається="взуття й сумка третьою річчю не рахуються навмисно: вони є в "
                  "кожному образі за побудовою, і з ними правило було б тривіально "
                  "істинним. Сам «мінімум трьох» — `[convention]` без названого "
                  "автора: корпус закрив пошук першоджерела на третьому проході",
        поріг=float(СТЕЛЯ_ФОКУСІВ), вимір=0.0, повна=1.0))]


# Дуга, у межах якої два кольори — ОДИН голос (відлуння), а не два фокуси: градуси КОЛА
# ХУДОЖНИКА (КОЛІР-Р2, рядок 2693; стала й міра — `колір_річ.ДУГА_ВІДЛУННЯ`, `відлуння_тону`).
# Та сама стала групує акценти K-COL-05 (`колір_хрома.відлуння.СУСІДНІ`,
# `суд_від_моделі._СУСІДНІ_ТОНИ`): правило фокусу й правило відлуння мусять
