"""Факти крамниці з названою величиною й одиницею для запису речі нового виду."""
import re
from collections import Counter
from functools import lru_cache

import фід_атрибути as атрибути
from фід_взуття import ВИСОТА_КАБЛУКА_МАКС_СМ, _смуга_з_параметрів


_СМ = r"(?:см|cм|cm)"
_ОДИНИЦЯ = re.compile(rf"(?<![\w]){_СМ}\b", re.I)
_ЧИСЛО = r"\d{1,3}(?:[.,]\d+)?"
_ВИМІР = re.compile(rf"({_ЧИСЛО})(?:\s*[-–—]\s*({_ЧИСЛО}))?\s*({_СМ})?\.?\s*", re.I)
_РОЗМІР = r"(?:[\w./]+(?:[-–][\w./]+)*|one size)"
_МІТКА_РОЗМІРУ = re.compile(rf"{_РОЗМІР}$", re.I)
_ПАРА_РОЗМІРУ = re.compile(rf"({_РОЗМІР})\s+[-–—:=]\s*(.+)", re.I)
_СТОВПЕЦЬ_РОЗМІРУ = re.compile(r"розмір|міжнарод|українськ|^int|^eu(?:$|/)|^it$|^ua$|^usa?$|^uk$|^eur|^euro|^france", re.I)
_СТОВПЕЦЬ_МІРКИ = re.compile(
    r"обхват|окружн|об[\s’'є]*м|довжин|ширин|висот|зріст|ріст|груд|тал[іїи]|стег|бед[ре]|плеч|заміри", re.I
)
_МІРКИ_ПОЛІВ = {
    "каблук": re.compile(r"^висота (?:підбор|каблук)", re.I),
    "халява": re.compile(r"^висота халяв", re.I),
    "устілка": re.compile(r"довжина устілки", re.I),
    "посадка_см": re.compile(r"^висота посадки(?:\s|$)", re.I),
    "рукав_см": re.compile(r"^довжина рукава(?:\s|,|$)", re.I),
    "плечі_см": re.compile(r"^ширина плечей(?:\s|,|$)", re.I),
    "ланцюг": re.compile(r"^довжина ланцюж?к?а(?:\s|,|$)", re.I),
}
_КОДИ_МІРОК = {
    "каблук_см": "каблук", "халява_см": "халява", "довжина_см": "ланцюг",
}


def _вимір(значення, одиниця=False):
    """Зберігає число або впорядковану вилку, коли є одиниця в полі."""
    м = _ВИМІР.fullmatch(str(значення).replace("\u200b", "").strip())
    if not м or not (одиниця or м[3]):
        return None
    числа = [float(ч.replace(",", ".")) for ч in м.groups()[:2] if ч is not None]
    if len(числа) == 1:
        return числа[0]
    return числа if числа[0] <= числа[1] else None


def _мірка(значення, одиниця="cm"):
    """Оформлює значення з його одиницею й джерелом."""
    return {"value": значення, "unit": одиниця, "source": "крамниця"}


def _довжини(назва, значення):
    """Розбирає одне число, вилку чи явно підписані значення за розмірами."""
    одиниця = bool(_ОДИНИЦЯ.search(назва))
    значення = значення.replace("\u200b", "").replace("\xa0", " ")
    одне = _вимір(значення, одиниця)
    if одне is not None:
        return одне, {}
    частини = re.split(r"[,;]\s*(?=[\w./]+\s+[-–—:=])", значення)
    пари = [_ПАРА_РОЗМІРУ.fullmatch(ч.strip()) for ч in частини]
    if not all(пари):
        return None, {}
    # Одиниця в назві або наприкінці одного списку стосується всіх значень списку.
    одиниця = одиниця or bool(re.search(rf"{_СМ}\.?\s*$", значення, re.I))
    ряд = {п[1]: _вимір(п[2], одиниця) for п in пари}
    if len(ряд) != len(пари) or any(ч is None for ч in ряд.values()):
        return None, {}
    межі = [ч for в in ряд.values() for ч in (в if isinstance(в, list) else (в,))]
    return min(межі) if min(межі) == max(межі) else [min(межі), max(межі)], ряд


def _цілий_виріб(ключ, слот):
    """Відділяє поділ речі від деталей, які мають власну мірку."""
    if "довжин" not in ключ or атрибути.ДОВЖИНА_НЕ_ПОДІЛ.search(ключ):
        return False
    return "від талії" not in ключ or слот == "низ"


def довжина_крамниці(офер, слот):
    """Бере заявлену довжину виробу й, за наявності, сумісну геометрію для суду."""
    if слот not in атрибути.ДОВЖИНА_ТОЧКА_СЛОТА:
        return None
    пар = офер.get("параметри") or {}
    кандидати = []
    for назва, сире in пар.items():
        ключ = назва.lstrip("~•· ").strip().lower()
        if not _цілий_виріб(ключ, слот):
            continue
        значення, розміри = _довжини(ключ.replace("_", " "), сире)
        if значення is not None:
            # Перевага явній довжині всього виробу. Довжини швів і спинки лишаються окремими визначеннями.
            рівень = 2 if "виробу" in ключ else 1 if атрибути._точки_назви(ключ, слот) else 0
            кандидати.append((рівень, ключ, значення, розміри))
    if not кандидати:
        текст = f"{офер.get('назва') or ''} {пар.get('опис') or офер.get('опис') or ''}"
        for збіг in атрибути.ДОВЖИНА_ОПИСОМ.finditer(текст.replace("\u200b", "")):
            ключ, сире = збіг.group(1).lower(), збіг[0]
            if "від талії" in ключ and слот != "низ":
                continue
            число = re.search(rf"({_ЧИСЛО})\s*{_СМ}\b", сире, re.I)
            if число:
                кандидати.append((0, ключ, float(число[1].replace(",", ".")), {}))
    if not кандидати:
        return None
    бал = max(к[0] for к in кандидати)
    найкращі = [к for к in кандидати if к[0] == бал]
    _, ключ, значення, розміри = найкращі[0]
    точки = атрибути._точки_назви(ключ, слот) or атрибути.ДОВЖИНА_ТОЧКА_СЛОТА[слот]
    if any(в != значення or р != розміри or
           (атрибути._точки_назви(к, слот) or атрибути.ДОВЖИНА_ТОЧКА_СЛОТА[слот]) != точки
           for _, к, в, р in найкращі):
        return None
    межі = значення if isinstance(значення, list) else [значення, значення]
    низ, верх = атрибути.ДОВЖИНА_МЕЖІ_СМ
    if not низ <= межі[0] <= межі[1] <= верх:
        return None
    факт = _мірка(значення)
    if розміри:
        факт["by_size"] = розміри
    точка, зсув = атрибути.точка_довжини(точки)
    if точка and зсув is not None:
        факт["reference"] = точка
        факт["uncertainty_cm"] = round(max(атрибути.ДОВЖИНА_ДОПУСК_СМ, (межі[1] - межі[0]) / 2) + зсув, 1)
    return факт


def _колонка(заголовок, клітини):
    """Тримає клітини мірки окремо від розмірних позначок."""
    if _СТОВПЕЦЬ_МІРКИ.search(заголовок) and not _СТОВПЕЦЬ_РОЗМІРУ.match(заголовок):
        мірки = [_вимір(к, bool(_ОДИНИЦЯ.search(заголовок))) for к in клітини]
        return ("cm", мірки) if any(в is not None for в in мірки) else (None, [])
    if _СТОВПЕЦЬ_РОЗМІРУ.match(заголовок):
        return "size", [к if _МІТКА_РОЗМІРУ.fullmatch(к) else None for к in клітини]
    return None, []


@lru_cache(maxsize=256)
def таблиця_крамниці(сире):
    """Зберігає прив'язку числа до одиниці, колонки та розміру в обох орієнтаціях таблиці."""
    if not сире:
        return None
    рядки = [[к.strip() for к in р.split("|")] for р in сире.split(";") if р.strip()]
    if len(рядки) < 2:
        return None
    шапка, *дані = рядки
    дані = [р for р in дані if len(р) == len(шапка) and any(р)]
    if len(шапка) < 2 or not дані:
        return None
    if _СТОВПЕЦЬ_РОЗМІРУ.match(шапка[0]) and all(_МІТКА_РОЗМІРУ.fullmatch(к) for к in шапка[1:]):
        шапка, дані = [шапка[0], *(р[0] for р in дані)], [list(р) for р in zip(шапка[1:], *(р[1:] for р in дані))]
    повтори = Counter(к.casefold() for к in шапка)
    колонки = []
    for заголовок, клітини in zip(шапка, zip(*дані)):
        if повтори[заголовок.casefold()] == 1:
            одиниця, розібрано = _колонка(заголовок, клітини)
            if одиниця:
                колонки.append((заголовок, одиниця, розібрано))
    види = [од for _, од, _ in колонки]
    if "cm" not in види or "size" not in види:
        return None
    дані = [р for р in zip(*(к for _, _, к in колонки))
            if any(в is not None and од == "size" for в, од in zip(р, види))
            and any(в is not None and од == "cm" for в, од in zip(р, види))]
    if not дані:
        return None
    return {"source": "крамниця", "columns": [[з, од] for з, од, _ in колонки], "rows": дані}


def мірки_крамниці(офер, слот):
    """Витягає типізовані факти з каталогу, доступні й без запису з фото."""
    пар = офер.get("параметри") or {}
    факти = {}
    if довжина := довжина_крамниці(офер, слот):
        факти["довжина_виробу"] = довжина
    if таблиця := таблиця_крамниці(пар.get("таблиця_мірок")):
        факти["таблиця_мірок"] = таблиця
    if слот in ("низ", "комплект") and (посадка := пар.get("посадка")) in ("висока", "середня", "низька"):
        факти["посадка_пояса"] = _мірка(посадка, "class")
    значення = {}
    for назва, сире in пар.items():
        ключ = назва.lstrip("~•· ").strip().lower()
        поле = _КОДИ_МІРОК.get(ключ) if ключ != "довжина_см" or слот == "кольє" else None
        поле = поле or next((п for п, рег in _МІРКИ_ПОЛІВ.items() if рег.search(ключ)), None)
        if поле:
            знач = _вимір(сире, bool(_ОДИНИЦЯ.search(ключ.replace("_", " "))))
            if знач is not None:
                значення.setdefault(поле, []).append(знач)
    for поле, числа in значення.items():
        if all(ч == числа[0] for ч in числа):
            факти[поле] = _мірка(числа[0])
    каблук = факти.get("каблук", {}).get("value")
    if каблук is not None and (слот != "взуття" or _смуга_з_параметрів(пар)
                               or max(каблук if isinstance(каблук, list) else [каблук]) > ВИСОТА_КАБЛУКА_МАКС_СМ):
        del факти["каблук"]
    return факти
