# ── K-LNG-04 (тема-4 VII.4, Koutsoumpis та ін. 2026): НЕ СПЕРЕЧАТИСЬ ІЗ ПЕРЕКОНАННЯМ ──
# Людина каже «горизонтальна смужка мене повнить». Природний хід — виправити («насправді
# не повнить»). Дані: у того, хто вірить, що смуги повнять, віра не корелює зі сприйняттям;
# виправлення не змінює того, що людина бачить, і коштує довіри. Тому переконання
# маршрутизується в канал ВЕТО/ПРЕФЕРЕНЦІЇ: смугасті речі просто не пропонуються, і
# бриф несе заборону на спростування. ЩО ЦЕ МІНЯЄ: на ager є ≥3 смугасті речі («в
# полоску»); з переконанням у профілі вони випадають із пулу композитора — до 24.08.2026
# переконання не мало куди лягти й нічого не міняло.
# (формула, слова-збіги, назва, режим). Режим «вето» — клас мотиву читається зі слова назви
# (смужка, клітинка); «преференція» — коли ознака (масштаб принта) у фіді НЕ читається:
# «великий принт» на фіді без масштабу вирізав би всі 58 принтованих речей ager, тобто
# розширив би межу людини за неї. Преференція йде в бриф як напрям, не у фільтр.
_ПЕРЕКОНАННЯ_ПРИНТ = [
    (r"горизонтальн\w*\s+(смуг|смуж|полос)\w*", ["смуж", "смуг", "полос", "stripe"], "горизонтальна смужка", "вето"),
    (r"(смуг|смуж|полос)\w*\s+\w*\s*(повн|товст|розшир|полн|толст|не (мо[єе]|люблю|ношу))", ["смуж", "смуг", "полос", "stripe"], "смужка", "вето"),
    (r"(кліт\w+|клетк\w+)\s+\w*\s*(повн|полн|не (мо[єе]|люблю|ношу))", ["кліт", "клет", "check"], "клітинка", "вето"),
    (r"(велик\w+|крупн\w+)\s+(принт|візерун|узор|рисун)\w*", ["принт", "візерун", "узор", "рисун", "print"], "великий принт", "преференція"),
]

def переконання_принт(текст):
    """Розбір висловлених переконань/відмов щодо принта → dict(вето=[…], переконання=[…]).
    Правило не судить, чи переконання правдиве: воно бере його як межу людини (K-LNG-04)."""
    import re as _re
    вето, перелік, преференції = [], [], []
    t = str(текст or "").lower()
    for ф, слова, назва, режим in _ПЕРЕКОНАННЯ_ПРИНТ:
        if _re.search(ф, t):
            перелік.append(назва)
            if режим == "вето":
                for w in слова:
                    if w not in вето: вето.append(w)
            else:
                преференції.append(dict(що=назва, слова=слова,
                                        чому="ознака у фіді не читається — фільтр розширив би межу людини за неї"))
    if перелік:
        try:
            import trace as _СЛ
            _СЛ.запис("K-LNG-04", "переконання про принт → вето, без спростування", "profile.переконання_принт",
                      значення=", ".join(перелік), сила=None, напрям="канал вето/преференції")
        except Exception:
            pass
    return dict(вето=вето, преференції=преференції, переконання=перелік,
                інструкція=("не спростовувати: «%s» — межа людини, не помилка; речі під нею не "
                            "пропонуються, у поясненні тема не піднімається" % "; ".join(перелік))
                if перелік else None)


def жорстке_ні_фільтр(речі, жорстке_ні):
    """АБСОЛЮТНИЙ фільтр, не вага. Повертає (лишились, відкинуті_з_причиною).

    Збіг шукається по полях, які річ реально несе: крій, тканина/текстура, колір,
    тип, відкрита зона, довжина — і по назві як останній резерв. Це навмисно грубо:
    хибне спрацювання коштує однієї показаної речі, пропуск коштує довіри."""
