def аудит(F, source="protocolized", зріст_см=None, драп=None, нагода=None,
          сценарій_входи=None, тіло_виміри=None):
    """Що в профілі виміряне, що заявлене, і чи не пора переміряти."""
    рядки, треба_знімок = [], []
    for k, v in F.items():
        if not isinstance(v, dict) or k.startswith("_"): continue
        p = v.get("походження")
        if p:
            рядки.append(dict(риса=k, джерело=p["джерело"], σ=p["σ_L"],
                              зсув=p["зсув_L"], було=p["було_L"], стало=v["L"]))
            if abs(p["зсув_L"]) > ПЕРЕМІРЯТИ and p["джерело"].startswith("заявлено"):
                треба_знімок.append(k)
        else:
            рядки.append(dict(риса=k, джерело=f"вимір ({source})",
                              σ=Σ["вимір_протокол"] if source == "protocolized"
                                else Σ["вимір_селфі"], зсув=0.0))
    м = масштаб(зріст_см)
    # R-PC-04 (T1·hard): стимульна елісітація — ПЕРВИННЕ джерело колориту, фото лише assist.
    # Доти драп питався тільки аварійно (outfit.білі, і лише коли підтон ненадійний І в
    # образі є білі речі) — тобто первинне джерело збиралось рідше за допоміжне. Тут воно
    # стає частиною онбордингу поряд зі зростом.
    бракує = []
    if м["масштаб_особи"] is None:
        бракує.append(м["питання"])
    дані_драпу = драп if isinstance(драп, dict) else {}
    for поле, оп in ДРАП_ПИТАННЯ.items():
        if not дані_драпу.get(поле):
            бракує.append(оп["питання"])
    if not нагода:
        бракує.append(НАГОДА_ПИТАННЯ["питання"])
    for поле, оп in ТІЛО_ПИТАННЯ.items():
        if not (тіло_виміри or {}).get(поле):
            бракує.append(оп["питання"])
    for поле, оп in СЦЕНАРІЙ_ПИТАННЯ.items():
        if not (сценарій_входи or {}).get(поле):
            бракує.append(оп["питання"])
    ел = None
    if дані_драпу:
        try:
            import palette as _P
            ел = _P.тепло_з_елісітації(**{k: v for k, v in дані_драпу.items()
                                          if k in ДРАП_ПИТАННЯ})
        except Exception:
            ел = None
    return dict(риси=рядки, σ_профілю=σ_профілю(F, source),
                масштаб_особи=м["масштаб_особи"],
                елісітація=ел,
                контракт_онбордингу=dict(зріст_см="140–200",
                                         нагода=НАГОДА_ПИТАННЯ["значення"],
                                         **{k: v.get("значення", "текст")
                                            for k, v in СЦЕНАРІЙ_ПИТАННЯ.items()},
                                         **{k: v["значення"] for k, v in ПОГОДА_КОНТРАКТ.items()},
                                         **{k: v["значення"]
                                                                for k, v in ДРАП_ПИТАННЯ.items()}),
                бракує_онбордингу=(бракує or None),
                # політика була константою, яку ніхто не читав; тепер вона їде в контракт,
                # тобто той, хто будує діалог, бачить заборону, а не мусить її пам'ятати
                не_питати=dict(траур=ТРАУР_ПОЛІТИКА),
                переміряти=треба_знімок or None,
                вимога=(f"заявлений зсув понад {ПЕРЕМІРЯТИ} L* — потрібен новий знімок: "
                        "далі вікна каталогу рахуються на числі, якого ніхто не бачив"
                        if треба_знімок else None))

def вікна_біля_обличчя(F, source="protocolized"):
    """Наслідок правки в тому вигляді, в якому його бачить каталог."""
    o = контраст(F, source)
    if not o.get("доступно"): return None
    return dict(контраст=o["value_gap"], рівень=o["рівень"],
                вікно_темніше=O.цільове_вікно(o["L_шкіри"], o["value_gap"], True),
                вікно_світліше=O.цільове_вікно(o["L_шкіри"], o["value_gap"], False),
                σ=σ_профілю(F, source))

