def контраст(F, source="protocolized"):
    """Контраст особи з урахуванням макіяжу. Приріст додається до value_gap,
    але тягне за собою власну невизначеність — і вона входить у σ рішення."""
    o = O.контраст_особи(F, source)
    if not o.get("доступно"): return o
    # ── ТА САМА ФУНКЦІЯ, ЩО В РАНЗІ, ВІКНІ Й СУДІ (19.09.2026) ─────────────
    # Тут читався `F["_макіяж"]["приріст_контрасту"]` — слід шару правок, який
    # переїхав у лабораторію і на живому шляху не ставився ніколи; отже приріст
    # не додавався, а з нинішнім слідом `colorspace.додати_макіяж` (без такого
    # ключа) впав би KeyError, який `palette` P-PRT-02 ковтав у `except`.
    import face_contrast as _KC
    ліміт, важіль = _KC.дозволений_контраст(o)
    if важіль:
        o = dict(o, value_gap_база=o["value_gap"], value_gap=round(ліміт, 1),
                 важіль_макіяжу=важіль)
        # БУЛО 20/40 — власні пороги, розбіжні з outfit.контраст_особи (22/45). Через це
        # та сама людина потрапляла в різні гілки palette.розвилка залежно від шляху.
        o["рівень"] = O.рівень_контрасту(o["value_gap"])
    return o

def σ_профілю(F, source="protocolized"):
    """Сумарна невизначеність світлоти профілю: вимір + усі накладені правки.
    Саме це число має порівнюватись із маржею рішення в реєстр_правил._сила."""
    база = Σ["вимір_протокол"] if source == "protocolized" else Σ["вимір_селфі"]
    складові = [база]
    for k, v in F.items():
        if isinstance(v, dict) and v.get("походження"):
            складові.append(v["походження"]["σ_L"])
    if (F.get("_макіяж") or {}).get("приріст_контрасту"):   # слід лабораторії; продуктовий сліду σ не має
        складові.append(F["_макіяж"]["σ"])
    return round(math.sqrt(sum(x*x for x in складові)), 1)   # незалежні джерела

