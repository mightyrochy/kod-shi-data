"""Правки профілю. Ґрунтовний вимір — один раз; далі профіль ЗМІНЮЄТЬСЯ.

Чому це окремий шар, а не поле в картці. Кожна правка тягне за собою перерахунок
вікон, якими фільтрується каталог: перефарбоване волосся зсуває контраст особи, а
з ним — вікно L* біля обличчя; макіяж піднімає ефективний контраст лише у вечірньому
режимі; засмага рухає світлоту шкіри й ITA. Якщо правку не перерахувати, система
далі одягає людину, якої вже нема.

Головний поділ, який тут тримається: ВИМІРЯНЕ і ЗАЯВЛЕНЕ — не одне й те саме.
Протокольний знімок дає σ L*≈4. Фраза «я пофарбувалась у горіховий» не дає нічого,
крім наміру: у неї нема ні світлоти, ні хроми, а салонний результат розходиться із
задумом регулярно. Тому заявлена правка:
  · застосовується (система не має вдавати, що людина не змінилась),
  · але несе власну невизначеність, більшу за вимір,
  · і якщо зсув перевищує те, що профіль здатен пробачити, просить новий знімок.
"""
import math, copy
