def масштаб(зріст_см=None, риси_масштаб=None, джерело="заявлено"):
    """Неперервний `масштаб_особи` ∈ [0,1] для правил про масштаб принту (P-PRT-01).
    Замикає вхід, який доти був відсутній: правило вміло рахувати, але нікому було
    подати масштаб людини.

    Шкала КУСКОВО-ЛІНІЙНА, і це не косметика: якби кінці стандарту (152/182) мапились
    лінійно, середня українка (164 см) сіла б на 0.40, і «середній масштаб для всіх
    інших» діставався б людині вище за середню. Тому 152→0.0, 164→0.5, 182→1.0.

    `риси_масштаб` (розмір рис обличчя, 0..1) — другий канал того самого поняття
    (Raes міряє масштаб по рисах, не по зросту). Коли є обидва — беремо середнє й
    підіймаємо надійність; коли лише зріст — працюємо на ньому й кажемо це.
    Нема нічого — повертаємо None, і P-PRT-01 лишається інертним, як і був.

    `джерело`: 'заявлено' (онбординг, самозвіт — люди систематично додають собі
    сантиметри) чи 'виміряно'. Це вісь НАДІЙНОСТІ, окрема від сили правила."""
    if зріст_см is None and риси_масштаб is None:
        return dict(масштаб_особи=None, надійність=0.0,
                    нема="ні зросту, ні розміру рис",
                    питання="Який у вас зріст у сантиметрах? (потрібно, щоб підбирати "
                            "масштаб принту й пропорції, а не лише колір)",
                    контракт=dict(поле="зріст_см", діапазон="140–200",
                                  куди="онбординг, одне питання"))
    канали, ноти = [], []
    if зріст_см is not None:
        z = max(140.0, min(200.0, float(зріст_см)))
        м, ц, М = ЗРІСТ_ДСТУ["мін"], ЗРІСТ_ДСТУ["середній_UA"], ЗРІСТ_ДСТУ["макс"]
        if z <= ц:
            t = 0.5 * (z - м) / (ц - м)
        else:
            t = 0.5 + 0.5 * (z - ц) / (М - ц)
        канали.append(max(0.0, min(1.0, t)))
        ноти.append("зріст %.0f см → %.2f (152/164/182 як якорі)" % (z, канали[-1]))
        if not (м <= z <= М):
            ноти.append("зріст поза діапазоном типових фігур ДСТУ — екстраполяція, "
                        "правило про масштаб тут слабше")
    if риси_масштаб is not None:
        канали.append(max(0.0, min(1.0, float(риси_масштаб))))
        ноти.append("розмір рис → %.2f" % канали[-1])
    значення = sum(канали) / len(канали)
    надійність = (0.75 if len(канали) == 2 else 0.45)
    if джерело == "виміряно":
        надійність = min(1.0, надійність + 0.2)
    return dict(масштаб_особи=round(значення, 2), надійність=round(надійність, 2),
                канали=len(канали), джерело=джерело, чому="; ".join(ноти),
                тіри=dict(інтервал=ЗРІСТ_ДСТУ["тір_інтервалу"],
                          центр=ЗРІСТ_ДСТУ["тір_центру"],
                          відображення=ЗРІСТ_ДСТУ["тір_відображення"]),
                ламається="зріст не каже про пропорцію: 164 см з довгими ногами і 164 см "
                          "з довгим корпусом читаються по-різному; масштаб рис надійніший "
                          "для приобличчевої зони, зріст — для загального силуету")


