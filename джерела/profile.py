def мета_з_ваг(ваги_цілей, нагода=None, поріг_домінанти=0.15):
    """(мета, чому). Провідна мета з ваг цілей, умовних на нагоді.

    `поріг_домінанти` — наскільки провідна ціль має відірватись від наступної, щоб
    вважатись провідною. Без відриву мета лишається "лестити" (дефолт системи), і це
    сказано: рівні ваги означають, що людина не назвала пріоритету, а не що вона
    хоче лестити.

    ⚠ 0.15 — ФОЛЬКЛОРНА КОНСТАНТА. Джерела для порогу відриву нема; калібрується на
    реальних відповідях онбордингу."""
    if not ваги_цілей:
        return "лестити", ("ваг цілей нема — мета за замовчуванням «лестити». Це НЕ "
                           "нейтральний вибір: він припускає, що людина хоче подобатись, "
                           "і тема-6 §1.6 прямо каже, що це не для всіх")
    в = ваги_цілей.get(нагода) if (нагода and isinstance(ваги_цілей.get(нагода), dict)) else ваги_цілей
    в = {k: float(v) for k, v in в.items() if k in ЦІЛІ}
    if not в:
        return "лестити", "у вагах нема жодної відомої цілі — дефолт «лестити»"
    ранж = sorted(в.items(), key=lambda x: -x[1])
    провідна, w1 = ранж[0]
    w2 = ранж[1][1] if len(ранж) > 1 else 0.0
    if (w1 - w2) < поріг_домінанти:
        return "лестити", ("провідна ціль «%s» (%.2f) не відірвалась від «%s» (%.2f) "
                           "на %.2f — пріоритету не названо, мета лишається дефолтною"
                           % (провідна, w1, ранж[1][0] if len(ранж) > 1 else "—", w2,
                              поріг_домінанти))
    м = _МЕТА_ЗА_ЦІЛЛЮ.get(провідна, "лестити")
    без = ЦІЛІ_БЕЗ_ВАЖЕЛЯ.get(провідна)
    return м, ("провідна ціль «%s» (%.2f, відрив %.2f) → мета «%s». Вісь «увага не "
               "привертається ↔ привертається» міняє НАПРЯМ поради, не її силу "
               "(тема-6 §1.6). Відображення ціль→мета НАШЕ, не з джерела; сила soft"
               % (провідна, w1, w1 - w2, м)
               + (". ⚠ %s" % без if без else ""))


def ваги_за_нагодою(ваги_цілей, мікс_нагод):
    """Ваги цілей, усереднені по РЕАЛЬНОМУ міксу нагод людини.

    Навіщо: `ваги_цілей` можуть бути умовні на нагоді, а гардероб збирається під
    життя загалом. Тема-6 §1.5 велить ловити нагоди як ЧАСТКИ РЕАЛЬНОГО ЖИТТЯ —
    отже й цілі треба важити тими самими частками, інакше вихідна сукня важить
    стільки ж, скільки робоча блуза, якої людина потребує щодня."""
    if not ваги_цілей: return None, "ваг цілей нема"
    if not мікс_нагод or not isinstance(next(iter(ваги_цілей.values()), None), dict):
        return ваги_цілей, "ваги не умовні на нагоді або міксу нема — беруться як є"
    сума = sum(мікс_нагод.values()) or 1.0
    out = {}
    for нагода, частка in мікс_нагод.items():
        for ціль, w in (ваги_цілей.get(нагода) or {}).items():
            out[ціль] = out.get(ціль, 0.0) + float(w) * float(частка) / сума
    return (out or ваги_цілей), ("ваги усереднені по міксу нагод %s — гардероб "
                                 "збирається під реальний тиждень, не під найяскравішу "
                                 "нагоду" % {k: round(v/сума, 2) for k, v in мікс_нагод.items()})

# ── K-LNG-04 (тема-4 VII.4, Koutsoumpis та ін. 2026): НЕ СПЕРЕЧАТИСЬ ІЗ ПЕРЕКОНАННЯМ ──
# Людина каже «горизонтальна смужка мене повнить». Природний хід — виправити («насправді
# не повнить»). Дані: у того, хто вірить, що смуги повнять, віра не корелює зі сприйняттям;
# виправлення не змінює того, що людина бачить, і коштує довіри. Тому переконання
# маршрутизується в канал ВЕТО/ПРЕФЕРЕНЦІЇ: смугасті речі просто не пропонуються, і
# бриф несе заборону на спростування. ЩО ЦЕ МІНЯЄ: на ager є ≥3 смугасті речі («в
# полоску»); з переконанням у профілі вони випадають із пулу композитора — до 24.08.2026
# переконання не мало куди лягти й нічого не міняло.
# (формула, слова-збіги, назва, режим). Режим «вето» — клас мотиву читається зі слова назви
# (смужка, клітинка); «преференція» — коли ознака (масштаб принта) у фіді НЕ читається:
# «великий принт» на фіді без масштабу вирізав би всі 58 принтованих речей ager, тобто
# розширив би межу людини за неї. Преференція йде в бриф як напрям, не у фільтр.
_ПЕРЕКОНАННЯ_ПРИНТ = [
    (r"горизонтальн\w*\s+(смуг|смуж|полос)\w*", ["смуж", "смуг", "полос", "stripe"], "горизонтальна смужка", "вето"),
    (r"(смуг|смуж|полос)\w*\s+\w*\s*(повн|товст|розшир|полн|толст|не (мо[єе]|люблю|ношу))", ["смуж", "смуг", "полос", "stripe"], "смужка", "вето"),
    (r"(кліт\w+|клетк\w+)\s+\w*\s*(повн|полн|не (мо[єе]|люблю|ношу))", ["кліт", "клет", "check"], "клітинка", "вето"),
    (r"(велик\w+|крупн\w+)\s+(принт|візерун|узор|рисун)\w*", ["принт", "візерун", "узор", "рисун", "print"], "великий принт", "преференція"),
]

def переконання_принт(текст):
    """Розбір висловлених переконань/відмов щодо принта → dict(вето=[…], переконання=[…]).
    Правило не судить, чи переконання правдиве: воно бере його як межу людини (K-LNG-04)."""
    import re as _re
    вето, перелік, преференції = [], [], []
    t = str(текст or "").lower()
    for ф, слова, назва, режим in _ПЕРЕКОНАННЯ_ПРИНТ:
        if _re.search(ф, t):
            перелік.append(назва)
            if режим == "вето":
                for w in слова:
                    if w not in вето: вето.append(w)
            else:
                преференції.append(dict(що=назва, слова=слова,
                                        чому="ознака у фіді не читається — фільтр розширив би межу людини за неї"))
    if перелік:
        # П.14: `trace` — модуль ядра, `запис` тотальний; застава ковтала лише
        # помилку коду в рядку вище й лишала лог без K-LNG-04, не сказавши нікому.
        import trace as _СЛ
        _СЛ.запис("K-LNG-04", "переконання про принт → вето, без спростування", "profile.переконання_принт",
                  значення=", ".join(перелік), сила=None, напрям="канал вето/преференції")
    return dict(вето=вето, преференції=преференції, переконання=перелік,
                інструкція=("не спростовувати: «%s» — межа людини, не помилка; речі під нею не "
                            "пропонуються, у поясненні тема не піднімається" % "; ".join(перелік))
                if перелік else None)


