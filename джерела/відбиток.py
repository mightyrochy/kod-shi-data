"""ВІДБИТОК СИСТЕМИ: що в коді написано насправді.

ЧОМУ ЦЕ ПРИЛАД, А НЕ ДОКУМЕНТ. Опис системи, набраний руками, описує НАМІР
автора. Тут усе дістається з AST поточних файлів, тож документ описує КОД:
хто кого кличе, що приймає, що повертає, і під якою умовою правило спрацьовує.
Розійтись із кодом він не може за побудовою.

ЧИМ ЦЕ ВІДРІЗНЯЄТЬСЯ ВІД СУСІДІВ:
  `зведення.py` — чи правило ДІЄ (слід у виході);
  `правила.py`  — що про правило каже КОРПУС і що з ним робила сесія;
  цей файл      — як правило НАПИСАНЕ і як воно повʼязане з рештою коду.

ЧОТИРИ ЧАСТИНИ ВИХОДУ:
  1. КАРТА ВИКЛИКІВ — ребра модуль→модуль, узяті з реальних `X.f(...)`, а не з
     `import`: імпорт без виклику зв'язком не є (і в цьому проєкті такі були).
  2. ФУНКЦІЇ — сигнатура з дефолтами, ключі того, що функція ПОВЕРТАЄ (коли це
     dict), і хто її кличе. «Хто кличе» рахується по всьому дереву, тож нуль
     викликачів тут — це твердження, а не здогад.
  3. ПРАВИЛА В КОДІ — кожне місце емісії: файл:рядок, охопна функція, УМОВИ, під
     якими виконується цей рядок (ланцюг `if` угору по дереву), сила, і сам вираз
     суті так, як він написаний.
  4. ТАБЛИЦІ ПРАВИЛ — і це не додаток, а структура: частина правил цієї системи
     оголошена ДАНИМИ, а не кодом. У 25 таблицях модульного рівня лежать 186
     унікальних ID, і один шлях коду обслуговує їх усі. Тому в місцях емісії ID
     часто стоїть не літералом, а `прав` чи `сп["правило"]`; генератор показує,
     ЗВІДКИ ця змінна береться в охопній функції.

ЧОГО ЦЕЙ ФАЙЛ НЕ КАЖЕ: чи правило ПРАВЕ, чи воно доходить до виходу (це
`зведення.py`) і чи сказане ним придатне (це читання промпта, `A10`).
УМОВИ беруться СИНТАКСИЧНО: `if` угору по дереву. Ранній `return`, `continue` і
виняток вище по функції тут не видно — вони теж гейтять, і їх треба читати очима.

Прогін:  python3 відбиток.py [--md ФАЙЛ]
"""
import ast, io, os, sys, glob, re, collections

_ТУТ = os.path.dirname(os.path.abspath(__file__)) or "."
# Прилади й одноразові скрипти у відбиток не йдуть: він про СИСТЕМУ.
_НЕ_СИСТЕМА = re.compile(r'^(audit_|measure_|gate_|test_|run_|build_|_)|'
                         r'^(мутанти|гейти_нові|звірка|зведення|правила|відбиток|'
                         r'проба_правила|аудит_слотів|траса_петлі|чистка_каталогу|'
                         r'скласти|підфід|rule_genus|корпус|status)\.py$')
ID_ПРАВИЛА = re.compile(r'^[KRPE]-[A-ZА-Я0-9]{2,5}-\d{2}[a-zа-я]?$')


def _джерело(вузол, рядки, максимум=200):
    """Вихідний текст виразу, стиснутий в один рядок."""
    try:
        с = ast.get_source_segment("\n".join(рядки), вузол)
    except Exception:
        с = None
    if not с:
        return "?"
    с = " ".join(с.split())
    return с if len(с) <= максимум else с[:максимум - 1] + "…"


class Дерево:
    """Розібраний модуль із батьківськими зв'язками (ast їх не тримає)."""

    def __init__(self, шлях):
        self.імя = os.path.basename(шлях)
        self.текст = io.open(шлях, encoding="utf-8", errors="replace").read()
        self.рядки = self.текст.split("\n")
        self.дерево = ast.parse(self.текст)
        self.батько = {}
        for вузол in ast.walk(self.дерево):
            for дитя in ast.iter_child_nodes(вузол):
                self.батько[дитя] = вузол

    def вгору(self, вузол):
        while вузол in self.батько:
            вузол = self.батько[вузол]
            yield вузол

    def охопна(self, вузол):
        for п in self.вгору(вузол):
            if isinstance(п, (ast.FunctionDef, ast.AsyncFunctionDef)):
                return п.name
        return None

    def умови(self, вузол):
        """Ланцюг `if`, під якими цей рядок виконується, знизу вгору.

        Гілка `else` дає «НЕ (…)»: інакше умова читалась би навпаки, і опис
        правила стверджував би протилежне тому, що робить код.
        """
        out, поточний = [], вузол
        for п in self.вгору(вузол):
            if isinstance(п, ast.If):
                у_else = any(поточний is x or поточний in ast.walk(x) for x in п.orelse)
                т = _джерело(п.test, self.рядки, 120)
                out.append(("НЕ (%s)" % т) if у_else else т)
            elif isinstance(п, (ast.For, ast.While)):
                out.append("цикл: " + _джерело(п, self.рядки, 60).split(":")[0])
            поточний = п
        return list(reversed(out))


def _сигнатура(f, рядки):
    а = f.args
    імена = [x.arg for x in а.posonlyargs] + [x.arg for x in а.args]
    деф = [None] * (len(імена) - len(а.defaults)) + [
        _джерело(d, рядки, 40) for d in а.defaults]
    части = ["%s=%s" % (n, d) if d is not None else n for n, d in zip(імена, деф)]
    if а.vararg: части.append("*" + а.vararg.arg)
    if а.kwonlyargs:
        if not а.vararg: части.append("*")
        for x, d in zip(а.kwonlyargs, а.kw_defaults):
            части.append("%s=%s" % (x.arg, _джерело(d, рядки, 40)) if d is not None else x.arg)
    if а.kwarg: части.append("**" + а.kwarg.arg)
    return "%s(%s)" % (f.name, ", ".join(части))


def _повертає(f, рядки):
    """Що функція віддає: ключі dict, або форма виразу."""
    ключі, форми = [], []
    for вузол in ast.walk(f):
        if not isinstance(вузол, ast.Return) or вузол.value is None:
            continue
        v = вузол.value
        if isinstance(v, ast.Dict):
            for k in v.keys:
                if isinstance(k, ast.Constant) and isinstance(k.value, str):
                    ключі.append(k.value)
        elif isinstance(v, ast.Call) and isinstance(v.func, ast.Name) and v.func.id == "dict":
            ключі += [kw.arg for kw in v.keywords if kw.arg]
        elif isinstance(v, ast.Tuple):
            форми.append("(%s)" % ", ".join(_джерело(e, рядки, 22) for e in v.elts))
        elif isinstance(v, (ast.List, ast.ListComp)):
            форми.append("[…]")
        elif isinstance(v, ast.Constant) and v.value is None:
            форми.append("None")
        else:
            форми.append(_джерело(v, рядки, 40))
    порядок = list(dict.fromkeys(ключі))
    return порядок, list(dict.fromkeys(форми))[:4]


def зібрати(корінь=None):
    корінь = корінь or _ТУТ
    файли = [f for f in sorted(glob.glob(os.path.join(корінь, "*.py")))
             if not _НЕ_СИСТЕМА.search(os.path.basename(f))]
    дерева = {}
    for ш in файли:
        try:
            дерева[os.path.basename(ш)] = Дерево(ш)
        except SyntaxError as e:
            print("  ⚠ %s не розбирається: %s" % (os.path.basename(ш), e))
    модулі = {k[:-3] for k in дерева}

    функції, виклики = {}, collections.defaultdict(set)
    ребра = collections.Counter()
    for імя, d in дерева.items():
        псевдо = {}                     # alias → module
        for вузол in ast.walk(d.дерево):
            if isinstance(вузол, ast.Import):
                for a in вузол.names:
                    if a.name in модулі: псевдо[a.asname or a.name] = a.name
            elif isinstance(вузол, ast.ImportFrom) and вузол.module in модулі:
                for a in вузол.names:
                    псевдо[a.asname or a.name] = вузол.module
        for вузол in d.дерево.body:
            if isinstance(вузол, (ast.FunctionDef, ast.AsyncFunctionDef)):
                кл, фр = _повертає(вузол, d.рядки)
                функції[(імя, вузол.name)] = dict(
                    файл=імя, імя=вузол.name, рядок=вузол.lineno,
                    сигнатура=_сигнатура(вузол, d.рядки),
                    повертає_ключі=кл, повертає_форми=фр,
                    доки=(ast.get_docstring(вузол) or "").split("\n")[0][:150],
                    приватна=вузол.name.startswith("_"))
        for вузол in ast.walk(d.дерево):
            if not isinstance(вузол, ast.Call):
                continue
            f = вузол.func
            if isinstance(f, ast.Attribute) and isinstance(f.value, ast.Name):
                ціль = псевдо.get(f.value.id)
                if ціль:
                    ребра[(імя[:-3], ціль)] += 1
                    виклики[(ціль + ".py", f.attr)].add(імя)
            elif isinstance(f, ast.Name):
                виклики[(імя, f.id)].add(імя)
    return дерева, функції, виклики, ребра


def таблиці(дерева, мінімум=2):
    """Присвоєння модульного рівня, що несуть ID правил.

    ЧОМУ ЦЕ ОКРЕМА ЧАСТИНА. Правило в цій системі буває оголошене не гілкою
    коду, а РЯДКОМ ТАБЛИЦІ: реєстр констант із тірами, карта регістрів
    гейт/репліка, чекліст, перелік заблокованих відсутнім входом. Один шлях коду
    тоді обслуговує десятки правил, і без цієї частини вони виглядали б як
    «нема в коді», хоч насправді керуються даними.
    """
    out = []
    for імя, d in дерева.items():
        for вузол in d.дерево.body:
            if not isinstance(вузол, ast.Assign):
                continue
            цілі = [x.id for x in вузол.targets if isinstance(x, ast.Name)]
            if not цілі:
                continue
            іди = sorted({к.value for к in ast.walk(вузол.value)
                          if isinstance(к, ast.Constant) and isinstance(к.value, str)
                          and ID_ПРАВИЛА.match(к.value)})
            if len(іди) < мінімум:
                continue
            поля = sorted({k.value for к in ast.walk(вузол.value)
                           if isinstance(к, ast.Dict)
                           for k in к.keys
                           if isinstance(k, ast.Constant) and isinstance(k.value, str)})
            out.append(dict(файл=імя, імя=цілі[0], рядок=вузол.lineno,
                            правил=len(іди), ід=іди, поля=поля[:14],
                            форма=type(вузол.value).__name__))
    out.sort(key=lambda x: -x["правил"])
    return out


def _звідки_ід(d, вузол, вираз_вузол):
    """Де в охопній функції береться змінна, що несе ID правила."""
    if isinstance(вираз_вузол, ast.Subscript):
        return _джерело(вираз_вузол, d.рядки, 60)
    if not isinstance(вираз_вузол, ast.Name):
        return _джерело(вираз_вузол, d.рядки, 60) if вираз_вузол is not None else "?"
    імя_зм = вираз_вузол.id
    охопна = None
    for п in d.вгору(вузол):
        if isinstance(п, (ast.FunctionDef, ast.AsyncFunctionDef)):
            охопна = п; break
    if охопна is None:
        return імя_зм
    джерела = []
    for a in охопна.args.args + охопна.args.kwonlyargs:
        if a.arg == імя_зм:
            джерела.append("параметр `%s` функції `%s`" % (імя_зм, охопна.name))
    for п in ast.walk(охопна):
        if isinstance(п, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == імя_зм for t in п.targets):
            джерела.append("`%s`" % _джерело(п, d.рядки, 80))
        elif isinstance(п, ast.For):
            цілі = [п.target] if isinstance(п.target, ast.Name) else list(
                getattr(п.target, "elts", []))
            if any(isinstance(t, ast.Name) and t.id == імя_зм for t in цілі):
                джерела.append("цикл `for %s in %s`" % (
                    _джерело(п.target, d.рядки, 30), _джерело(п.iter, d.рядки, 50)))
    return "; ".join(dict.fromkeys(джерела)) or імя_зм


def правила(дерева):
    """Кожне місце, де код НАРОДЖУЄ знахідку правила."""
    out = collections.defaultdict(list)
    for імя, d in дерева.items():
        for вузол in ast.walk(d.дерево):
            if not isinstance(вузол, ast.Call):
                continue
            f = вузол.func
            звідки = None
            if isinstance(f, ast.Name) and f.id in ("_зн",):
                звідки = "_зн"
            elif isinstance(f, ast.Attribute) and f.attr in ("_зн", "запис"):
                звідки = f.attr
            elif isinstance(f, ast.Name) and f.id == "dict":
                звідки = "dict"
            if not звідки:
                continue
            ід = сила = суть = None
            if звідки in ("_зн", "запис"):
                поз = [a for a in вузол.args]
                if поз and isinstance(поз[0], ast.Constant) and isinstance(поз[0].value, str) \
                        and ID_ПРАВИЛА.match(поз[0].value):
                    ід = поз[0].value
                    # ДВІ РІЗНІ СИГНАТУРИ, І ПЛУТАТИ ЇХ НЕ МОЖНА (перевірено в trace.py):
                    #   outfit._зн(правило, СИЛА, СУТЬ, речі, чому, …)
                    #   trace.запис(правило, ЯРЛИК, ВУЗОЛ, значення=, сила=, напрям=)
                    # Перша версія підписувала другий аргумент «СИЛА» в обох, і в
                    # звіті K-COMP-02 виходило «СИЛА: "якір першим…"», «СУТЬ:
                    # "composer._портфель"» — тобто ярлик як сила, а імʼя вузла як
                    # суть. Опис, що бреше про власне джерело, гірший за відсутній.
                    if звідки == "_зн":
                        if len(поз) > 1: сила = _джерело(поз[1], d.рядки, 40)
                        if len(поз) > 2: суть = _джерело(поз[2], d.рядки, 260)
                    else:
                        if len(поз) > 1: суть = _джерело(поз[1], d.рядки, 200)
                        кв_с = next((k.value for k in вузол.keywords if k.arg == "сила"), None)
                        if кв_с is not None: сила = _джерело(кв_с, d.рядки, 40)
            else:
                кв = {k.arg: k.value for k in вузол.keywords if k.arg}
                п = кв.get("правило")
                if isinstance(п, ast.Constant) and isinstance(п.value, str) \
                        and ID_ПРАВИЛА.match(п.value):
                    ід = п.value
                    if "сила" in кв: сила = _джерело(кв["сила"], d.рядки, 40)
                    if "суть" in кв: суть = _джерело(кв["суть"], d.рядки, 260)
            if not ід:
                # ID у ЗМІННІЙ — правило керується таблицею. Це не пропуск: без
                # цієї гілки табличні правила зникали б із відбитка мовчки.
                сирий = (вузол.args[0] if (звідки in ("_зн", "запис") and вузол.args)
                         else next((k.value for k in вузол.keywords if k.arg == "правило"), None))
                if сирий is None or (isinstance(сирий, ast.Constant)
                                     and isinstance(сирий.value, str)):
                    continue
                out.setdefault("__непрямі__", []).append(dict(
                    файл=імя, рядок=вузол.lineno, форма=звідки,
                    функція=d.охопна(вузол), умови=d.умови(вузол),
                    ід_вираз=_джерело(сирий, d.рядки, 60),
                    звідки=_звідки_ід(d, вузол, сирий),
                    суть=(_джерело(вузол.args[2], d.рядки, 200)
                          if (звідки == "_зн" and len(вузол.args) > 2) else None)))
                continue
            кв_усі = sorted({k.arg for k in вузол.keywords if k.arg})
            out[ід].append(dict(
                файл=імя, рядок=вузол.lineno, форма=звідки,
                функція=d.охопна(вузол), умови=d.умови(вузол),
                сила=сила, суть=суть, поля=кв_усі))
    return out


