def _джерело(вузол, рядки, максимум=200):
    """Вихідний текст виразу, стиснутий в один рядок."""
    try:
        с = ast.get_source_segment("\n".join(рядки), вузол)
    except Exception:
        с = None
    if not с:
        return "?"
    с = " ".join(с.split())
    return с if len(с) <= максимум else с[:максимум - 1] + "…"


class Дерево:
    """Розібраний модуль із батьківськими зв'язками (ast їх не тримає)."""

    def __init__(self, шлях):
        self.імя = os.path.basename(шлях)
        self.текст = io.open(шлях, encoding="utf-8", errors="replace").read()
        self.рядки = self.текст.split("\n")
        self.дерево = ast.parse(self.текст)
        self.батько = {}
        for вузол in ast.walk(self.дерево):
            for дитя in ast.iter_child_nodes(вузол):
                self.батько[дитя] = вузол

    def вгору(self, вузол):
        while вузол in self.батько:
            вузол = self.батько[вузол]
            yield вузол

    def охопна(self, вузол):
        for п in self.вгору(вузол):
            if isinstance(п, (ast.FunctionDef, ast.AsyncFunctionDef)):
                return п.name
        return None

    def умови(self, вузол):
        """Ланцюг `if`, під якими цей рядок виконується, знизу вгору.

        Гілка `else` дає «НЕ (…)»: інакше умова читалась би навпаки, і опис
        правила стверджував би протилежне тому, що робить код.
        """
        out, поточний = [], вузол
        for п in self.вгору(вузол):
            if isinstance(п, ast.If):
                у_else = any(поточний is x or поточний in ast.walk(x) for x in п.orelse)
                т = _джерело(п.test, self.рядки, 120)
                out.append(("НЕ (%s)" % т) if у_else else т)
            elif isinstance(п, (ast.For, ast.While)):
                out.append("цикл: " + _джерело(п, self.рядки, 60).split(":")[0])
            поточний = п
        return list(reversed(out))


def _сигнатура(f, рядки):
    а = f.args
    імена = [x.arg for x in а.posonlyargs] + [x.arg for x in а.args]
    деф = [None] * (len(імена) - len(а.defaults)) + [
        _джерело(d, рядки, 40) for d in а.defaults]
    части = ["%s=%s" % (n, d) if d is not None else n for n, d in zip(імена, деф)]
    if а.vararg: части.append("*" + а.vararg.arg)
    if а.kwonlyargs:
        if not а.vararg: части.append("*")
        for x, d in zip(а.kwonlyargs, а.kw_defaults):
            части.append("%s=%s" % (x.arg, _джерело(d, рядки, 40)) if d is not None else x.arg)
    if а.kwarg: части.append("**" + а.kwarg.arg)
    return "%s(%s)" % (f.name, ", ".join(части))


def _повертає(f, рядки):
    """Що функція віддає: ключі dict, або форма виразу."""
    ключі, форми = [], []
    for вузол in ast.walk(f):
        if not isinstance(вузол, ast.Return) or вузол.value is None:
            continue
        v = вузол.value
        if isinstance(v, ast.Dict):
            for k in v.keys:
                if isinstance(k, ast.Constant) and isinstance(k.value, str):
                    ключі.append(k.value)
        elif isinstance(v, ast.Call) and isinstance(v.func, ast.Name) and v.func.id == "dict":
            ключі += [kw.arg for kw in v.keywords if kw.arg]
        elif isinstance(v, ast.Tuple):
            форми.append("(%s)" % ", ".join(_джерело(e, рядки, 22) for e in v.elts))
        elif isinstance(v, (ast.List, ast.ListComp)):
            форми.append("[…]")
        elif isinstance(v, ast.Constant) and v.value is None:
            форми.append("None")
        else:
            форми.append(_джерело(v, рядки, 40))
    порядок = list(dict.fromkeys(ключі))
    return порядок, list(dict.fromkeys(форми))[:4]


def зібрати(корінь=None, модулі=None):
    """`модулі` — явний перелік імен без `.py`; за замовчуванням вантаж продукту.

    ПАРАМЕТР З'ЯВИВСЯ ЗАРАДИ ОДНОГО СВІДКА (Н-V34-066). `audit_contracts` питає
    «яких функцій не кличе ніхто» про ІНШУ множину — усі живі модулі теки, а не
    лише ті, що їдуть у вантажі від `bridge` (поза вантажем лишаються, серед
    інших, `status_перевірки` й `семплер`). Дати йому власний обхід означало б
    завести другого свідка з протилежними відповідями — рівно те, чим хворий
    розділ 4 того файла. Тому обхід один, а множина — аргумент.
    """
    корінь = корінь or _ТУТ
    файли = [os.path.join(корінь, м + ".py")
             for м in sorted(модулі if модулі is not None
                             else склад.модулі_системи(корінь))]
    дерева = {}
    for ш in файли:
        try:
            дерева[os.path.basename(ш)] = Дерево(ш)
        except SyntaxError as e:
            print("  ⚠ %s не розбирається: %s" % (os.path.basename(ш), e))
    модулі = {k[:-3] for k in дерева}

    функції, виклики = {}, collections.defaultdict(set)
    ребра = collections.Counter()
    for імя, d in дерева.items():
        псевдо = {}                     # alias → module
        for вузол in ast.walk(d.дерево):
            if isinstance(вузол, ast.Import):
                for a in вузол.names:
                    if a.name in модулі: псевдо[a.asname or a.name] = a.name
            elif isinstance(вузол, ast.ImportFrom) and вузол.module in модулі:
                for a in вузол.names:
                    псевдо[a.asname or a.name] = вузол.module
        for вузол in d.дерево.body:
            if isinstance(вузол, (ast.FunctionDef, ast.AsyncFunctionDef)):
                кл, фр = _повертає(вузол, d.рядки)
                функції[(імя, вузол.name)] = dict(
                    файл=імя, імя=вузол.name, рядок=вузол.lineno,
                    сигнатура=_сигнатура(вузол, d.рядки),
                    повертає_ключі=кл, повертає_форми=фр,
                    доки=(ast.get_docstring(вузол) or "").split("\n")[0][:150],
                    приватна=вузол.name.startswith("_"))
        for вузол in ast.walk(d.дерево):
            if not isinstance(вузол, ast.Call):
                continue
            f = вузол.func
            if isinstance(f, ast.Attribute) and isinstance(f.value, ast.Name):
                ціль = псевдо.get(f.value.id)
                if ціль:
                    ребра[(імя[:-3], ціль)] += 1
                    виклики[(ціль + ".py", f.attr)].add(імя)
            elif isinstance(f, ast.Name):
                виклики[(імя, f.id)].add(імя)
    return дерева, функції, виклики, ребра


