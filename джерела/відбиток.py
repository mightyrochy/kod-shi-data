def _верхні_функції(імя_файла, дерева, корінь):
    """Імена функцій модульного рівня. Файл може бути поза `дерева` (прилад)."""
    d = дерева.get(імя_файла)
    if d is not None:
        тіло = d.дерево.body
    else:
        ш = os.path.join(корінь or _ТУТ, імя_файла)
        if not os.path.exists(ш):
            return set(), None
        тіло = ast.parse(io.open(ш, encoding="utf-8", errors="replace").read()).body
    return {в.name for в in тіло
            if isinstance(в, (ast.FunctionDef, ast.AsyncFunctionDef))}, тіло


def входи_рядком(дерева, корінь=None):
    """{(файл, імя)} — функції, які кличуть РЯДКОМ, а не викликом.

    Порожній результат означає, що диспетчер перейменували або перенесли, і це
    видно одразу: винятків тоді не стає, і розділ 4 червоніє цілим списком.
    """
    вих = set()
    for файл, диспетчер in ДИСПЕТЧЕРИ:
        свої, тіло = _верхні_функції(файл, дерева, корінь)
        if тіло is None:
            continue
        for вузол in тіло:
            if not (isinstance(вузол, (ast.FunctionDef, ast.AsyncFunctionDef))
                    and вузол.name == диспетчер):
                continue
            for в in ast.walk(вузол):
                if isinstance(в, ast.Name) and в.id in свої:
                    вих.add((файл, в.id))
    for де_рядки, чиї_функції in ІМЕНА_РЯДКОМ:
        свої, _ = _верхні_функції(чиї_функції, дерева, корінь)
        _, тіло = _верхні_функції(де_рядки, дерева, корінь)
        if тіло is None or not свої:
            continue
        for вузол in ast.walk(ast.Module(body=тіло, type_ignores=[])):
            if (isinstance(вузол, ast.Constant) and isinstance(вузол.value, str)
                    and вузол.value in свої):
                вих.add((чиї_функції, вузол.value))
    return вих


def нікому(функції, виклики, винятки=()):
    """Функції, яких не кличе НІХТО — навіть власний модуль.

    ОДИН СВІДОК НА ОДНЕ ПИТАННЯ (Н-V34-066). Це твердження раніше робили двоє:
    тут — обхід AST, у `audit_contracts.мертві_функції` — регулярка по тексту.
    Регулярка зараховувала САМ РЯДОК `def імя(` за виклик, тож множина «викликані»
    завжди накривала «визначені» і розділ 4 звітував «мертвих нема» — при 48
    іменах тут. Двоє свідків із протилежними відповідями гірші за одного:
    читають того, хто зелений. Лишився цей.

    `винятки` — точки входу, які кличуть рядком (`входи_рядком`).
    """
    вин = set(винятки)
    вих = []
    for d in sorted(функції.values(), key=lambda x: (x["файл"], x["рядок"])):
        хто = виклики.get((d["файл"], d["імя"]), set())
        if (хто - {d["файл"]}) or d["файл"] in хто:
            continue
        if (d["файл"], d["імя"]) in вин:
            continue
        вих.append(d)
    return вих


def таблиці(дерева, мінімум=2):
    """Присвоєння модульного рівня, що несуть ID правил.

    ЧОМУ ЦЕ ОКРЕМА ЧАСТИНА. Правило в цій системі буває оголошене не гілкою
    коду, а РЯДКОМ ТАБЛИЦІ: реєстр констант із тірами, карта регістрів
    гейт/репліка, чекліст, перелік заблокованих відсутнім входом. Один шлях коду
    тоді обслуговує десятки правил, і без цієї частини вони виглядали б як
    «нема в коді», хоч насправді керуються даними.
    """
    out = []
    for імя, d in дерева.items():
        for вузол in d.дерево.body:
            if not isinstance(вузол, ast.Assign):
                continue
            цілі = [x.id for x in вузол.targets if isinstance(x, ast.Name)]
            if not цілі:
                continue
            іди = sorted({к.value for к in ast.walk(вузол.value)
                          if isinstance(к, ast.Constant) and isinstance(к.value, str)
                          and _ЦІЛИЙ_ІД(к.value)})
            if len(іди) < мінімум:
                continue
            поля = sorted({k.value for к in ast.walk(вузол.value)
                           if isinstance(к, ast.Dict)
                           for k in к.keys
                           if isinstance(k, ast.Constant) and isinstance(k.value, str)})
            out.append(dict(файл=імя, імя=цілі[0], рядок=вузол.lineno,
                            правил=len(іди), ід=іди, поля=поля[:14],
                            форма=type(вузол.value).__name__))
    out.sort(key=lambda x: -x["правил"])
    return out


def _звідки_ід(d, вузол, вираз_вузол):
    """Де в охопній функції береться змінна, що несе ID правила."""
    if isinstance(вираз_вузол, ast.Subscript):
        return _джерело(вираз_вузол, d.рядки, 60)
    if not isinstance(вираз_вузол, ast.Name):
        return _джерело(вираз_вузол, d.рядки, 60) if вираз_вузол is not None else "?"
    імя_зм = вираз_вузол.id
    охопна = None
    for п in d.вгору(вузол):
        if isinstance(п, (ast.FunctionDef, ast.AsyncFunctionDef)):
            охопна = п; break
    if охопна is None:
        return імя_зм
    джерела = []
    for a in охопна.args.args + охопна.args.kwonlyargs:
        if a.arg == імя_зм:
            джерела.append("параметр `%s` функції `%s`" % (імя_зм, охопна.name))
    for п in ast.walk(охопна):
        if isinstance(п, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == імя_зм for t in п.targets):
            джерела.append("`%s`" % _джерело(п, d.рядки, 80))
        elif isinstance(п, ast.For):
            цілі = [п.target] if isinstance(п.target, ast.Name) else list(
                getattr(п.target, "elts", []))
            if any(isinstance(t, ast.Name) and t.id == імя_зм for t in цілі):
                джерела.append("цикл `for %s in %s`" % (
                    _джерело(п.target, d.рядки, 30), _джерело(п.iter, d.рядки, 50)))
    return "; ".join(dict.fromkeys(джерела)) or імя_зм


def правила(дерева):
    """Кожне місце, де код НАРОДЖУЄ знахідку правила."""
    out = collections.defaultdict(list)
    for імя, d in дерева.items():
        for вузол in ast.walk(d.дерево):
            if not isinstance(вузол, ast.Call):
                continue
            f = вузол.func
            звідки = None
            if isinstance(f, ast.Name) and f.id in ("_зн",):
                звідки = "_зн"
            elif isinstance(f, ast.Attribute) and f.attr in ("_зн", "запис"):
                звідки = f.attr
            elif isinstance(f, ast.Name) and f.id == "dict":
                звідки = "dict"
            if not звідки:
                continue
            ід = сила = суть = None
            if звідки in ("_зн", "запис"):
                поз = [a for a in вузол.args]
                if поз and isinstance(поз[0], ast.Constant) and isinstance(поз[0].value, str) \
                        and _ЦІЛИЙ_ІД(поз[0].value):
                    ід = поз[0].value
                    # ДВІ РІЗНІ СИГНАТУРИ, І ПЛУТАТИ ЇХ НЕ МОЖНА (перевірено в trace.py):
                    #   outfit._зн(правило, СИЛА, СУТЬ, речі, чому, …)
                    #   trace.запис(правило, ЯРЛИК, ВУЗОЛ, значення=, сила=, напрям=)
                    # Перша версія підписувала другий аргумент «СИЛА» в обох, і в
                    # звіті K-COMP-02 виходило «СИЛА: "якір першим…"», «СУТЬ:
                    # "composer._портфель"» — тобто ярлик як сила, а імʼя вузла як
                    # суть. Опис, що бреше про власне джерело, гірший за відсутній.
                    if звідки == "_зн":
                        if len(поз) > 1: сила = _джерело(поз[1], d.рядки, 40)
                        if len(поз) > 2: суть = _джерело(поз[2], d.рядки, 260)
                    else:
                        if len(поз) > 1: суть = _джерело(поз[1], d.рядки, 200)
                        кв_с = next((k.value for k in вузол.keywords if k.arg == "сила"), None)
                        if кв_с is not None: сила = _джерело(кв_с, d.рядки, 40)
            else:
                кв = {k.arg: k.value for k in вузол.keywords if k.arg}
                п = кв.get("правило")
                if isinstance(п, ast.Constant) and isinstance(п.value, str) \
                        and _ЦІЛИЙ_ІД(п.value):
                    ід = п.value
                    if "сила" in кв: сила = _джерело(кв["сила"], d.рядки, 40)
                    if "суть" in кв: суть = _джерело(кв["суть"], d.рядки, 260)
            if not ід:
                # ID у ЗМІННІЙ — правило керується таблицею. Це не пропуск: без
                # цієї гілки табличні правила зникали б із відбитка мовчки.
                сирий = (вузол.args[0] if (звідки in ("_зн", "запис") and вузол.args)
                         else next((k.value for k in вузол.keywords if k.arg == "правило"), None))
                if сирий is None or (isinstance(сирий, ast.Constant)
                                     and isinstance(сирий.value, str)):
                    continue
                out.setdefault("__непрямі__", []).append(dict(
                    файл=імя, рядок=вузол.lineno, форма=звідки,
                    функція=d.охопна(вузол), умови=d.умови(вузол),
                    ід_вираз=_джерело(сирий, d.рядки, 60),
                    звідки=_звідки_ід(d, вузол, сирий),
                    суть=(_джерело(вузол.args[2], d.рядки, 200)
                          if (звідки == "_зн" and len(вузол.args) > 2) else None)))
                continue
            кв_усі = sorted({k.arg for k in вузол.keywords if k.arg})
            # СУФІКСНИЙ ВАРІАНТ РАХУЄТЬСЯ ОКРЕМО, АЛЕ ПРИПИСУЄТЬСЯ БАЗІ.
            # Варіант із суфіксом — не окреме правило, і власного запису в
            # корпусі він не має. Ключем іде БАЗА (інакше відбиток заводив би
            # фантомне правило, якого нема в жодній темі), а сам варіант
            # лишається видимим у полі `варіант` цього місця емісії — без нього
            # «код емітить правило» і «код емітить його варіант» були б одним
            # рядком, тобто варіант зникав би мовчки.
            out[ІП.база(ід)].append(dict(
                файл=імя, рядок=вузол.lineno, форма=звідки,
                функція=d.охопна(вузол), умови=d.умови(вузол),
                варіант=(ід if ІП.суфікс(ід) else None),
                сила=сила, суть=суть, поля=кв_усі))
    return out


