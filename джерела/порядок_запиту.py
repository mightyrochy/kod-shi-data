# -*- coding: utf-8 -*-
"""Порядок переліку в запиті до моделі: ярусами, усередині ярусу — сідом ЗАПИТУ.

ЧОМУ ЦЕ Є (В-1, 26.09.2026, рішення власника: «порядок речей перемішувати»). Модель бере
згори: на прогоні власника 25.09 перша річ слота — 12 % її виборів проти 3 % за рівного
шансу, перша третина — 68 % проти 33 % (Д-1, PR #355, `проби/повтор_позиція.py`). А
порядком, яким перелік їхав моделі, був порядок КОДУ — колірна відстань композитора,
коло семплера, розвід рук, — тож «згори» щоразу стояли ті самі речі.

ЩО ТУТ. Кожен запит, що несе моделі перелік, з якого вона вибирає (складання — пул,
ремонт і повнота — вітрина, вибір — образи), дістає СВІЙ сід (`сід_запиту`: сід руки +
крок) і свій порядок; обидва їдуть у етапи руки (`показ.html`: `запит.порядок`, файл
вердиктів) записом `запис`.
ЯРУСИ (`ярус`) — те, що порядком каже ЇЇ СЛОВО, а не код, лишається на своєму місці:
  0 — її явний вибір: річ за її бажанням, річ обраного нею кольору, її власна річ;
  1 — решта переліку;
  2 — речі, що вже стояли в її образах цього сценарію (рядок 159: «Зібрати ще раз»
      показує нове).
Усередині ярусу кожна позиція — рівним шансом.

ЧОГО ЦЕ НЕ РУХАЄ. Список коду (`кандидати`): з його порядку роздаються номери речей
(`пакет_моделі.номери_речей`), і розбір кожної відповіді руки рахує ту саму нумерацію
наново — тож перемішується лише КОПІЯ, що їде моделі. Сід 0 — «сіда нема» (тести, CLI):
порядок не рухається, як у `семплер._перемішати`.

РЕБРА. `random`, імʼя поля утримання з `семплер` (лист) і — ліниво, у
`перемішати_дріт` — імена списків дроту з `протокол` (одне імʼя на систему).
"""
import random

import семплер as _СМ

# Ключі запису порядку в етапі руки: сід запиту, крок і перелік — номерами речей
# (`слоти`) або ід образів (`образи`), рівно в тому порядку, у якому їх прочитала модель.
КРОКИ = ("compose", "repair", "completeness", "select", "assess", "tournament", "set", "final")

# Сід запиту від імені кроку НЕ залежить (СІД-1, рядок 221): код кроку — внутрішня мова
# (латиницею), а `random.Random` читає колишній рядок — байти UTF-8 (hex), без яких
# перемішування кожного запиту, тобто відповіді моделі й знімки стенда, були б інші.
# Новий крок додається сюди з будь-яким СВОЇМ hex; у мапі нема — береться сам код.
КЛЮЧ_СІДА = {
    "compose": "d181d0bad0bbd0b0d0b4d0b0d0bdd0bdd18f",
    "repair": "d180d0b5d0bcd0bed0bdd182",
    "completeness": "d0bfd0bed0b2d0bdd0bed182d0b0",
    "select": "d0b2d0b8d0b1d196d180",
    "assess": "d0bed186d196d0bdd0bad0b0",
    "tournament": "d182d183d180d0bdd196d180",
    "set": "d181d0bad0bbd0b0d0b4",
    "final": "d184d196d0bdd0b0d0bb",
}


# Солі перемішування (СІД-2, рядок 740): код — латиницею, hex — колишні байти UTF-8 того ж слова.
СІЛЬ = {
    "groups": "d0b3d180d183d0bfd0b8",
    "outfits": "d0bed0b1d180d0b0d0b7d0b8",
    "tournament": "d182d183d180d0bdd196d180",
    "set": "d181d0bad0bbd0b0d0b4",
}


def сіль(код):
    """Колишній рядок солі за кодом (латиницею); коду нема в мапі — він сам."""
    return bytes.fromhex(СІЛЬ[код]).decode("utf-8") if код in СІЛЬ else код


def сід_запиту(сід, крок, *ще):
    """Сід одного запиту: сід руки + імʼя кроку (+ номер спроби). 0 — «сіда нема».

    Рядковий ключ, а не `hash()`: хеш рядків рандомізується між процесами
    (PYTHONHASHSEED), а сід мусить відтворюватись із запису в файлі вердиктів."""
    сід = int(сід or 0)
    if not сід:
        return 0
    крок = str(крок)
    ключ = "|".join([str(сід), bytes.fromhex(КЛЮЧ_СІДА[крок]).decode("utf-8") if крок in КЛЮЧ_СІДА else крок]
                    + [str(x) for x in ще])
    return random.Random(ключ).randrange(1, 2 ** 31)


def ярус(r):
    """0 — її явний вибір, 2 — уже була в її образах цього сценарію, 1 — решта."""
    if not isinstance(r, dict):
        return 1
    if r.get("вже_був"):
        return 2
    if (r.get("за_бажанням") or r.get(_СМ.ПОЛЕ_УТРИМАННЯ)
            or r.get("власна") or r.get("закріплена")):
        return 0
    return 1


def перемішати(список, сід, мітка=""):
    """Копія списку: яруси по черзі, у кожному — перемішування сідом «сід|мітка|ярус»."""
    список = list(список or [])
    if not сід or len(список) < 2:
        return список
    яруси = ([], [], [])
    for r in список:
        яруси[ярус(r)].append(r)
    вих = []
    for я, частина in enumerate(яруси):
        random.Random("%d|%s|%d" % (сід, мітка, я)).shuffle(частина)
        вих += частина
    return вих


def перемішати_слоти(словник, сід):
    """{слот: [речі]} → копія, у якій кожен список перемішано `перемішати(…, мітка=слот)`."""
    return {с: перемішати(рч, сід, с) for с, рч in (словник or {}).items()}


def _номер(r):
    """Як модель називає річ: номер пулу «#12·03», а де його нема — id."""
    if isinstance(r, dict):
        return str(r.get("н") or r.get("id") or "")
    return str(r)


def запис(сід, крок, слоти=None, образи=None):
    """Запис порядку для етапу руки: {сід, крок, слоти: {слот: [н…]}, образи: [ід…]}."""
    з = {"сід": int(сід or 0), "крок": str(крок)}
    if слоти is not None:
        з["слоти"] = {с: [_номер(r) for r in рч] for с, рч in слоти.items()}
    if образи is not None:
        з["образи"] = [str(о) for о in образи]
    return з


def _склад(суд):
    """Підпис складу образів для солі вибору: речі кожного образу, у порядку вердикта.

    ПОРЯДОК ВИБОРУ — НЕ ОДНА ПЕРЕСТАНОВКА НА СІД (рядок 2770). Доти сіль була «сід|образи»: на
    одному сіді (стенд, розбір 02.10 — усі 40 сцен, обидві руки) кожен вибір діставав ту саму
    перестановку [3,1,2,4,0] над порядком відповіді ремонту. Ремонт кладе сміливий образ
    (`break`/`free`) п'ятим у 44 з 78 рук — і той щоразу стояв четвертим. Позиція образу в
    промпті вибору була функцією порядку ремонту, а не рівним шансом. Склад образів різний у
    кожній руці й сцені, тож перестановка теж; запис порядку (`запис.образи`) і вміст вердикта
    її відтворюють. Порожній підпис (образи без речей) — колишня сіль."""
    import протокол as _ПР
    частини = []
    for о in суд:
        т = (о or {}).get(_ПР.ТВІЙ_ОБРАЗ) if isinstance(о, dict) else None
        речі = (т or {}).get("речі") if isinstance(т, dict) else None
        if isinstance(речі, list) and речі:
            частини.append(",".join(str(x) for x in речі))
    return ("|" + ";".join(частини)) if частини else ""


def перемішати_дріт(обʼєкт, сід, крок, образи=False):
    """Запит на дроті (ремонт, повнота, вибір) → (копія з перемішаним переліком, запис).

    Перемішується те, з чого модель ВИБИРАЄ: у ремонті й повноті — списки `вітрина`; у
    виборі (`образи`) — сам список образів `вердикт` (вибір обирає один із них, а вітрини
    його промпт не несе — `повнота_образу.ВИБІР`). Склад образу не рухається: порядок
    речей усередині образу нічого не вибирає. Обʼєкт без переліку вертається як є, із
    записом без `слоти`/`образи`."""
    import протокол as _ПР
    if not isinstance(обʼєкт, dict):
        return обʼєкт, запис(сід, крок)
    вих = dict(обʼєкт)
    слоти = None
    if not образи and isinstance(вих.get("вітрина"), dict):
        вих["вітрина"] = перемішати_слоти(вих["вітрина"], сід)
        слоти = вих["вітрина"]
    ід = None
    if образи and isinstance(вих.get(_ПР.ВЕРДИКТ_ОБРАЗІВ), list):
        # образи — не речі: ярусів у них нема, позиція — рівним шансом
        суд = list(вих[_ПР.ВЕРДИКТ_ОБРАЗІВ])
        if сід and len(суд) > 1:
            random.Random("%d|%s%s" % (сід, сіль("outfits"), _склад(суд))).shuffle(суд)
        вих[_ПР.ВЕРДИКТ_ОБРАЗІВ] = суд
        ід = [((о or {}).get(_ПР.ТВІЙ_ОБРАЗ) or {}).get("ід") for о in суд if isinstance(о, dict)]
    return вих, запис(сід, крок, слоти=слоти, образи=ід)
