# ⚠ ОСНОВИ, А НЕ ПОВНІ СЛОВА — І ЦЕ НЕ КОСМЕТИКА, А ЗАКРИТТЯ МОВЧАЗНОЇ ДІРИ.
# `feed.взуттєві_атрибути` віддає ОСНОВУ («замш», «шкір», «екошкір»), бо українська
# словозміна інакше не ловиться. А тут стояли ПОВНІ слова («замша»), і перевірка
