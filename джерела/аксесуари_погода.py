# ═════════════════ 5. ПАНЧІШНІ ВИРОБИ (K-HOS-01/02) ═════════════════
def панчішні(речі, темп_c=None):
    """K-HOS-01 (щільність проти ваги тканини) + K-HOS-02 (ланка ланцюга).

    ЩО ЦЕ МІНЯЄ (before/after). before — колготки для системи не існували. after —
    колготки стають КЕРОВАНОЮ ЗМІННОЮ, якою система рятує пару, що інакше провалилась:
    ботильйони під спідницею проходять, якщо є колготки, що зводять ΔL* до взуття.

    ДВІ ЦІЛІ, ЯКІ МОЖУТЬ КОНФЛІКТУВАТИ, і система не має права мовчки обрати одну:
    колготки в тон ВЗУТТЯ подовжують ногу; колготки в тон ОДЯГУ узгоджують світлоту.

    ДЕ ЛАМАЄТЬСЯ: обидва джерела — медійні перекази допису, не консультації, і одне
    прямо конфліктує з іншими стилістками («стильно — тільки чорні»). Цей конфлікт САМ
    Є ДАНИМИ: припис про колготки в українському полі не консенсусний.
    """
    зн = []
    колготки = [р for р in речі if р.get("слот") == "колготи"]
    if not колготки:
        return зн
    низи = [р for р in речі if р.get("слот") in ("низ", "сукня", "комплект")]
    взуття = [р for р in речі if р.get("слот") == "взуття"]
    for к in колготки:
        назва = к.get("назва") or к.get("id") or "колготки"
        den = к.get("den")
        # ── K-HOS-01: щільність проти ваги тканини одягу ─────────────────────
        if den is not None and темп_c is not None:
            смуга = смуга_ніг(темп_c)
            if смуга:
                lo, hi = смуга["den"]
                d = float(den)
                поза = 0.0 if lo <= d <= hi else (lo - d if d < lo else d - hi)
                if поза > 0:
                    # ── БІК ВИХОДУ ЗІ СМУГИ СТОЇТЬ У СУТІ (08.09.2026) ──────
                    # ЩО ЦЕ МІНЯЄ (правило 3, before/after). `поза` — модуль
                    # відстані до смуги, знак у ньому втрачено; сама смуга (lo–hi)
                    # лишалась у `чому`, а «щільність зі смуги дня» — у `ремонт`.
                    # До ші доїжджає лише суть із силою, тож обидва виходи —
                    # ЗАТОНКО і ЗАЩІЛЬНО — приходили однаковою парою «число + °C»
                    # і з однаковою силою.
                    #   before (спідниця міді + колготки, прогін конвеєра):
                    #     · 100 DEN при +18 °C [1.0]
                    #     · 20 DEN при +5 °C [1.0]
                    #   after:
                    #     · щільніші за смугу дня: «колготки 100 DEN» 100 DEN при
                    #       +18 °C — узяти тонші [1.0]
                    #     · тонші за смугу дня: «колготки 20 DEN» 20 DEN при
                    #       +5 °C — узяти щільніші [1.0]
                    # ЧОМУ СТАРИЙ РЯДОК НЕДІЄВИЙ: щоб дізнатися бік, ші мусила б
                    # знати смугу дня напамʼять, а смуга лишилась у полі, якого
                    # вона не бачить; без боку заміна — монетка.
                    зн.append(dict(_зн("K-HOS-01", "soft" if поза >= 25 else "hint",
                        "%s за смугу дня: «%s» %s DEN при %+.0f °C — узяти %s"
                        % ("тонші" if d < lo else "щільніші", назва, den, темп_c,
                           "щільніші" if d < lo else "тонші"), [назва],
                        "щільність узгоджується з вагою тканини одягу: 5–20 під легкі (шовк, "
                        "віскоза), 30–50 під демісезонні (трикотаж, вовняні спідниці), "
                        "60–100 під зимові (вʼязані сукні, шерсть, твід). Смуга дня — %d–%d"
                        % (lo, hi),
                        ремонт="щільність зі смуги дня",
                        ламається="межі діапазонів суміжні й без зазору (20/30, 50/60) — це "
                                  "шкала ЗРУЧНОСТІ, не вимір; тому ознака рахується неперервно, "
                                  "а не трьома кошиками. Числа — від одного названого практика, "
                                  "не калібровані",
                        поріг=0.0, вимір=поза, повна=40.0),
                        сила_нп=round(min(1.0, поза / 40.0 + 0.25), 2),
                        сила_нп_джерело="вимір (DEN поза смугою)"))
        # ── K-HOS-02: ланка ланцюга «взуття ↔ нога ↔ низ» ────────────────────
        L_к = к.get("L")
        if L_к is None:
            continue
        ціль_взуття = взуття[0].get("L") if взуття and взуття[0].get("L") is not None else None
        ціль_низу = низи[0].get("L") if низи and низи[0].get("L") is not None else None
        if ціль_взуття is not None and ціль_низу is not None:
            Δвз, Δниз = abs(L_к - ціль_взуття), abs(L_к - ціль_низу)
            ближче = "взуття" if Δвз <= Δниз else "низу"
            # ── ЯКУ З ДВОХ ЦІЛЕЙ ОБРАНО Й ЧИМ ПЛАТИМО (08.09.2026) ─────────────
            # ЩО ЦЕ МІНЯЄ (правило 3, before/after). Правило САМЕ каже, що цілі дві
            # й вони конфліктують, — але назва ланки («взуття»/«низу») без назви
            # ЦІЛІ не дає ші нічого: обидві половини конфлікту виглядають однаково.
            # Друга ціль і спосіб її взяти лежали в `чому` й `ремонт`, а доїжджає
            # сама суть із силою.
            #   before (спідниця + черевики + колготки, той самий образ, різне L*):
            #     · колготки в тон взуття (ΔL* 2 проти 12) [0.7]
            #     · колготки в тон низу (ΔL* 1 проти 13) [0.78]
            #   after:
            #     · обрано колонку ноги: «колготки димчасті» ближчі до взуття
            #       (ΔL* 2 проти 12) — для узгодження світлоти звести ΔL* до низу [0.7]
            #     · обрано крок світлоти: «колготки димчасті» ближчі до низу
            #       (ΔL* 1 проти 13) — для довшої лінії ноги звести ΔL* до взуття [0.78]
            # ЧОМУ СТАРИЙ РЯДОК НЕДІЄВИЙ: він звітує ФАКТ («ближче до X»), а вибір
            # між двома цілями лишає невидимим, тож ші не може ані погодитись із
            # обраною ціллю, ані свідомо взяти другу.
            зн.append(dict(_зн("K-HOS-02", "soft",
                ("обрано колонку ноги: «%s» ближчі до взуття (ΔL* %.0f проти %.0f) — "
                 "для узгодження світлоти звести ΔL* до низу" if ближче == "взуття"
                 else "обрано крок світлоти: «%s» ближчі до низу (ΔL* %.0f проти %.0f) "
                      "— для довшої лінії ноги звести ΔL* до взуття")
                % (назва, min(Δвз, Δниз), max(Δвз, Δниз)),
                [назва],
                "це ДВІ РІЗНІ ЦІЛІ, і вони конфліктують: у тон взуття — подовжити ногу "
                "(колонка, K-SIL-07); у тон одягу — узгодити світлоту (крок світлоти, K-COL-01). "
                "Обрано ту, до якої колготки вже ближчі; система не має права мовчки обрати "
                "за вас іншу",
                ремонт=["якщо ціль — довжина лінії, звести ΔL* до ВЗУТТЯ",
                        "якщо ціль — мʼяка світлота, звести ΔL* до НИЗУ"],
                ламається="обидва джерела — медійні перекази допису, і одне прямо конфліктує з "
                          "іншими стилістками («стильно — тільки чорні»). Конфлікт САМ Є ДАНИМИ: "
                          "припис про колготки в українському полі не консенсусний. Матовість "
                          "тілесних — витрата з бюджету блиску, не окрема вимога",
                поріг=0.0, вимір=abs(Δвз - Δниз), повна=25.0),
                сила_нп=round(min(0.8, abs(Δвз - Δниз) / 25.0 + 0.3), 2),
                сила_нп_джерело="вимір (|ΔL* до взуття − ΔL* до низу|)"))
            _СЛ.запис("K-HOS-02", "колготки як керована змінна", "панчішні",
                      значення="ближче до %s" % ближче, сила=0.5, напрям="рятує пару")
    return зн
