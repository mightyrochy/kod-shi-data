# КЛАС ДЕФЕКТУ ВАРТО ЗАПАМʼЯТАТИ: два модулі домовились про поле, але не про
# ФОРМУ значення в ньому; аудит контрактів такого не бачить, бо поле пишеться й
# читається — розходиться словник значень, а не імен. Спіймано наскрізним прогоном
# із даними З ФІДУ, а не з тесту, і це єдиний спосіб, яким його можна спіймати.
ВОЛОГА_ВІДМОВА = ("замш", "нубук", "велюр")
# ДОПУСК НА МЕЖІ СМУГ (°C) — фольклорна константа, не калібрована: 4 °C — половина
# найвужчої смуги карти (2–10). Умова перегляду: вердикти «не для погоди» на взутті.
ДОПУСК_СМУГИ_НІГ = 4.0
ГЛАДКА_ПІДОШВА = ("гладк", "шкіряна підошва", "поліуретан гладк")


def смуга_ніг(темп_c):
    """Смуга температури для ніг. None, коли температури не дали — погода НЕ
    вигадується, як і в суд_образу.погода."""
    if темп_c is None:
        return None
    return next((d for lo, hi, d in СМУГИ_НІГ if lo <= темп_c < hi), None)


def сезон_і_погода(речі, темп_c=None, опади=None, реагенти=None):
    """K-WEA-04 / K-WEA-05 / K-WEA-06 / K-WEA-07 / K-WEA-08.

    ЩО ЦЕ МІНЯЄ (before/after). before — K-WEA-01 обіцяє, що погода АБСОЛЮТНО обмежує
    тканину, поділ І ВЗУТТЯ; взуттєва половина обіцянки була порожня, тому образ на
    січень і образ на травень діставали той самий список взуття. after — температура
    відсікає типи ДО будь-якого іншого правила, і на реальному фіді це найбільше
    скорочення пулу з усіх, які система робить.

    ДЕ ЛАМАЄТЬСЯ: «демісезон» покриває +2…+18 — надто широко, щоб бути смугою; сезон
    грубий фільтр, температура тонкий, і вони не взаємозамінні. Для аксесуарів (не
    взуття) сезон рідше є твердим вето: шовкова хустка взимку ПІД пальтом носиться
    цілком, вона просто не гріє. Тому правило розрізняє ФУНКЦІЮ і ПРИСУТНІСТЬ.
    """
    зн = []
    # Грубе паспортове «так» і плиткове «нема» перекладаються в слово корпусу на
    # тому самому шві, що й для `суд_образу.погода` (19.09.2026, РВ-3 З-2): без
    # цього «так, надворі мокро» важило для K-WEA-05 рівно стільки ж, скільки «ні».
    опади = _НАГОДА.канон_опади(опади)
    смуга = смуга_ніг(темп_c)
    if смуга is None:
        return зн
    for р in речі:
        сл, тип = р.get("слот"), р.get("тип")
        назва = р.get("назва") or р.get("id") or "річ"
        # ── K-WEA-07: тип взуття проти смуги ──────────────────────────────────
        if сл == "взуття" and тип:
            if тип not in смуга["типи"]:
                # НЕПЕРЕРВНО, не бінарно: наскільки далеко смуга речі від смуги дня.
                своя = _смуга_типу(тип)
                відстань = 0.0 if своя is None else _відстань_смуг(своя, темп_c)
                if своя is not None and відстань <= ДОПУСК_СМУГИ_НІГ:
                    # межа смуги — не вирок: тип із сусідньої смуги в межах допуску не є
                    # знахідкою (сила ≤ верифікація: рядки карти — hint, межі не калібровані)
                    _СЛ.запис("K-WEA-07", "тип на межі смуги ніг — у допуску", "сезон_і_погода",
                              значення=відстань, сила="hint")
                    continue
                сила_нп = round(min(1.0, 0.35 + відстань / 20.0), 2)
                зн.append(dict(_зн("K-WEA-07",
                    "soft" if сила_нп >= 0.5 else "hint",
                    "«%s» поза температурною смугою %+.0f °C" % (тип, темп_c),
                    [назва],
                    "смуга %+.0f °C бере %s; %s" % (темп_c, ", ".join(смуга["типи"]), смуга["матеріали"]),
                    ремонт="взяти тип зі смуги дня (%s)" % ", ".join(смуга["типи"][:3]),
                    ламається="карта ПОБУДОВАНА, не знайдена: жодне джерело не дало "
                              "температурних меж для типів взуття, межі смуг успадковані "
                              "від торса (K-WEA-02) без перевірки, що ноги мерзнуть так само; "
                              "смуга ігнорує тривалість надворі — +2 на пʼять хвилин до авта "
                              "й +2 на годину пішки різні рішення",
                    поріг=0.0, вимір=відстань, повна=20.0),
                    сила_нп=сила_нп,
                    сила_нп_джерело="вимір (власний: відстань між смугою типу й смугою дня, °C)"))
                _СЛ.запис("K-WEA-07", "тип поза смугою ніг", "сезон_і_погода",
                          значення="%s @ %+.0f°C" % (тип, темп_c), сила=сила_нп, напрям="звужує пул")
        # ── K-WEA-05: матеріал верху як погодні ворота ────────────────────────
        # ── ПОЛЕ ЧИТАЄТЬСЯ ТАК ШИРОКО, ЯК ФІД ЙОГО ПИШЕ (17.09.2026) ─────────
        # ЩО ТУТ СТОЯЛО: `матеріал_верху or тканина`. Обидва — ВЗУТТЄВІ поля.
        # Виміряно на `каталог_повний` (8 975 речей живого каталогу):
        #   `матеріал_верху` — 1 508 речей, УСІ взуття (його пише
        #                      `feed._взуттєві_поля`, і лише для слота «взуття»);
        #   `тканина`        — 0 речей: такого ключа запис каталогу не має зовсім.
        # Наслідок був не однаковий для двох правил, які цей рядок годує:
        #   K-WEA-05 працювало лише на взутті. Замшева СУМКА в мокрий сніг не
        #     діставала умови жодного разу, хоч тема-10 XXIX.2 називає її прямо
        #     («замша — вето, як у взутті»): 0 із 453 сумок каталогу;
        #   K-WEA-08 не працювало ВЗАГАЛІ: усі чотири його слоти (головний убір,
        #     шарф, рукавички, сумка) `матеріал_верху` не несуть за побудовою,
        #     тобто `мат` там був порожній рядок на 620 із 620 речей, і обидві
        #     гілки правила — літня форма в мороз і зимова в спеку — лишались
        #     мертві незалежно від погоди.
        # ЩО ЧИТАЄТЬСЯ ТЕПЕР, І В ЯКОМУ ПОРЯДКУ (той самий пріоритет, що в
        # `суд_образу.погода`, Н-outfit-2-091): вузьке слово першим, цілий склад
        # останнім. `матеріал_верху` — слово КАРТКИ взуття, воно найточніше й уже
        # вирішило «екошкіра ≠ шкіра»; `волокно` — нормалізоване слово за
        # найдовшим коренем (`verify.волокно_зі_слова`, 7 100 речей); `матеріал` —
        # цілий рядок складу магазину (`feed.матеріал_речі`, 7 193 речі), у ньому
        # основа шукається підрядком.
        # ЩО ЦЕ ЗМІНИЛО В ЧИСЛАХ (каталог_повний, 17.09.2026):
        #   K-WEA-05, речей із матеріалом відмови: 566 → 678 (сумки 0 → 44,
        #     взуття 566 → 634 — решту дало `волокно` там, де картка мовчить);
        #   K-WEA-08, речей із сезонним матеріалом: 0 → 192 (літніх 113: сумки 79,
        #     шарфи 25, головні убори 9; зимових 79: шарфи 36, убори 37, сумки 6).
        мат = (р.get("матеріал_верху") or р.get("волокно")
               or р.get("матеріал") or "").lower()
        # ── «МОКРО» ЧИТАЄТЬСЯ ЗІ СПИСКУ МОКРИХ, А НЕ З `bool()` (08.09.2026) ──
        # ЩО ТУТ СТОЯЛО: `bool(опади)`. Він істинний для БУДЬ-ЯКОГО непорожнього
        # рядка — тобто для КОЖНОГО документованого способу сказати «опадів нема»:
        #   profile.ПОГОДА_КОНТРАКТ  → 'немає'
        #   pipeline.СХЕМА_ПАСПОРТА  → 'ні'
        #   pipeline.паспорт_з_json  → 'невідомо'  (дефолт, коли модель не відповіла)
        # Виміряно 08.09.2026 наскрізь (accessory → pipeline.перевірити_образ →
        # composer._оцінити):
        #   опади='немає'    → K-WEA-05 strong, блокує=True, «замш у мокру погоду»
        #   опади='ні'       → те саме
        #   опади='невідомо' → те саме
        # Тобто замшеві черевики, сумка й рукавички відкидались у СУХУ погоду й на
        # дефолтному шляху конвеєра, з текстом, що прямо суперечить фактові дня.
        # Той самий домен у цьому ж репозиторії зроблено правильно: `суд_образу.погода`
        # питає `опади in ("дощ", "мокрий_сніг", "злива")`. Тут — той самий список,
        # читаний з одного місця, щоб два судження про одну погоду не розійшлися.
        # Третій диз'юнкт теж лагодиться: він робив мокро=True на `опади=False`
        # («температура ≤2 і опади не None»), тобто холод без опадів ставав мокрим.
        мокро = (опади in МОКРІ_ОПАДИ) or bool(реагенти) or (
            темп_c is not None and темп_c <= 2 and опади in МОКРІ_ОПАДИ)
        if мат and any(v in мат for v in ВОЛОГА_ВІДМОВА) and сл in ("взуття", "сумка", "рукавички"):
            if мокро:
                зн.append(dict(_зн("K-WEA-05", "strong",
                    "«%s» у мокру погоду з реагентами" % мат,
                    [назва],
                    "реагенти проникають усередину й руйнують структуру волокна зсередини; "
                    "сіль, залишена надовго, пересушує матеріал незворотно",
                    ремонт=["не в цю погоду БЕЗ обробки — просочити водовідштовхувальним "
                            "засобом тричі з повним просушуванням між нанесеннями",
                            "АБО гладка шкіра / текстиль на цей день"],
                    ламається="просочена замша — ІНШИЙ обʼєкт, ніж непросочена, і каталог "
                              "цього не знає. Тому правило видає УМОВУ, а не вето: воно не "
                              "має права мовчки викинути річ",
                    поріг=0.0, вимір=1.0, повна=1.0),
                    сила_нп=0.8, сила_нп_джерело="категорія (матеріал × наявність опадів)"))
                _СЛ.запис("K-WEA-05", "матеріал відмовляє у вологу", "сезон_і_погода",
                          значення=мат, сила=0.8, напрям="умова, не вето")
        # ── K-WEA-06: підошва ─────────────────────────────────────────────────
        під = (р.get("підошва") or "").lower()
        if сл == "взуття" and темп_c is not None and темп_c <= 2:
            if not під:
                зн.append(dict(_зн("K-WEA-06", "питання",
                    "зчеплення підошви невідоме, а це смуга ожеледі",
                    [назва],
                    "українські джерела дають перевірні ознаки: дуже тверда підошва погано "
                    "чіпляється за лід, повністю гладка — однозначне «ні» для зими, потрібен "
                    "протектор із глибоким різноспрямованим малюнком. Жодної з цих ознак "
                    "картка не несе",
                    ремонт="перевірити картку на слово про підошву або протектор",
                    ламається="«глибокий різноспрямований малюнок» із фото каталогу наявним "
                              "кодом не витягається; матеріал підошви в українських картках "
                              "присутній нерегулярно"),
                    сила_нп=0.0, сила_нп_джерело="входу нема (поле підошви порожнє)"))
            elif any(g in під for g in ГЛАДКА_ПІДОШВА):
                зн.append(dict(_зн("K-WEA-06", "strong",
                    "гладка підошва при %+.0f °C" % темп_c, [назва],
                    "повністю гладка підошва — однозначне «ні» для зими; ця ознака НЕ корелює "
                    "з ціною й може відкинути дорогу гарну пару, і саме тим корисна",
                    ремонт="протектор із глибоким різноспрямованим малюнком",
                    ламається="ознаки якісні, не числові; порога зчеплення джерела не дають",
                    поріг=2.0, вимір=float(темп_c)),
                    сила_нп=0.9, сила_нп_джерело="категорія (гладка підошва × смуга ожеледі)"))
        # ── K-WEA-08: сезон для решти аксесуарів, з розрізненням функції ──────
        if сл in ("головний_убір", "шарф", "рукавички", "сумка") and темп_c is not None:
            літня = _літній_матеріал(мат)
            зимова = _зимовий_матеріал(мат)
            if літня and темп_c < 2:
                зн.append(dict(_зн("K-WEA-08", "soft",
                    "«%s» при %+.0f °C не виконує теплової функції" % (мат, темп_c), [назва],
                    "сезон і волога — ворота для кожного аксесуара, не лише для ніг; але для "
                    "аксесуара це рідше тверде вето, ніж для взуття",
                    ремонт="зимова форма цього ж слота (фетр/вовна/кашемір/шкіра з підкладкою)",
                    ламається="ПРИСУТНІСТЬ ≠ ФУНКЦІЯ: шовкова хустка взимку ПІД пальтом "
                              "носиться цілком — вона просто не гріє. Без цього розрізнення "
                              "правило відкидатиме правильні образи",
                    поріг=2.0, вимір=float(темп_c), повна=15.0),
                    сила_нп=round(min(1.0, (2.0 - темп_c) / 15.0), 2),
                    сила_нп_джерело="вимір (власний: наскільки нижче межі, °C)"))
            elif зимова and темп_c >= 26:
                зн.append(dict(_зн("K-WEA-08", "soft",
                    "«%s» при %+.0f °C не носиться" % (мат, темп_c), [назва],
                    "вовняна хустка на +26 не носиться так само, як солома в січні",
                    ремонт="літня форма цього ж слота",
                    ламається=("та сама, що вище: правило розрізняє функцію й присутність, "
                               "і для верхнього краю смуги розрізнення слабше"),
                    поріг=26.0, вимір=float(темп_c), повна=10.0),
                    сила_нп=round(min(1.0, (темп_c - 26.0) / 10.0 + 0.4), 2),
                    сила_нп_джерело="вимір (власний: наскільки вище межі, °C)"))
    if зн:
        _СЛ.запис("K-WEA-04", "сезон як перший фільтр слота ніг", "сезон_і_погода",
                  значення="смуга %+.0f°C" % темп_c, сила=None, напрям="ворота перед преференціями")
    return зн


def _смуга_типу(тип):
    """Середина смуги, у яку тип потрапляє найтепліше. None — тип не в карті."""
    для = [(lo, hi) for lo, hi, d in СМУГИ_НІГ if тип in d["типи"]]
    if not для:
        return None
    lo = min(l for l, _ in для); hi = max(h for _, h in для)
    return (max(lo, -30.0), min(hi, 40.0))


def _відстань_смуг(своя, темп_c):
    lo, hi = своя
    if lo <= темп_c < hi:
        return 0.0
    return float(lo - темп_c if темп_c < lo else темп_c - hi)


