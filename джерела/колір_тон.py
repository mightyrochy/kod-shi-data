_ЕРФ_НАСИЧЕННЯ = 6.0   # erf(6) = 1 − 2·10⁻¹⁷: далі за 6·s від точки нормальний розподіл не відрізняється від 0 чи 1


def _ф(x, s):
    """Нормальна функція розподілу в точці x при масштабі s = σ·√2."""
    return 0.5 * (1.0 + math.erf(x / s))


def у_вікні(d, вікно, сигма):
    """Імовірність, що справжня відстань тонів на колі лежить у `вікно` (від, до, відкрита), коли
    виміряна — d (0…180°), а знак і зсув різниці розмиті гаусом σ (σ = 0 — тверда межа).

    Чому так: різниця тонів зі знаком δ ~ N(d, σ), а відстань — |δ|, згорнута на колі, тож вікну
    [a, b] відповідають відрізки [a, b] і [−b, −a] з кроком 360°; при σ → ∞ сила прямує до частки
    кола під вікном (той самий сектор — 1/12)."""
    a, b, відкрита = вікно
    if сигма <= 0.0:
        return 1.0 if ((d > a) if відкрита else (d >= a)) and d <= b else 0.0
    s, p = сигма * math.sqrt(2.0), 0.0
    for м in (-720.0, -360.0, 0.0, 360.0, 720.0):
        # відрізки [a, b] і [−b, −a] далі за _ЕРФ_НАСИЧЕННЯ·s від d дають 0 точно до double (erf уже ±1) — зсув пропущено
        if м - d - b > _ЕРФ_НАСИЧЕННЯ * s or м - d + b < -_ЕРФ_НАСИЧЕННЯ * s: continue
        if a == 0.0:   # відрізки зливаються в [−b, b]: середні члени скорочуються
            p += _ф(b + м - d, s) - _ф(-b + м - d, s)
        else:
            p += _ф(b + м - d, s) - _ф(a + м - d, s) + _ф(-a + м - d, s) - _ф(-b + м - d, s)
    return min(1.0, max(0.0, p))


def _у_вікні_меж(р, вікно, сигма):
    """(мін, макс) `у_вікні` для відстані з інтервалу р = (мін, макс): сила одногорба з вершиною в
    центрі вікна (0 — для вікна від нуля, 180 — для вікна до 180), тож мінімум — на кінці інтервалу,
    максимум — у найближчій до центру точці."""
    a, b, _ = вікно
    ц = 0.0 if a == 0.0 else 180.0 if b == 180.0 else (a + b) / 2.0
    return (min(у_вікні(р[0], вікно, сигма), у_вікні(р[1], вікно, сигма)),
            у_вікні(min(max(ц, р[0]), р[1]), вікно, сигма))


# ── ДУГА ТОНУ — ВІКНО З СИЛОЮ, ЩО ЗГАСАЄ ДО КРАЇВ ───────────────────────────────────────────────────
# Одна сила для всіх дуг тону: відстань тону речі до центру дуги (кут CIELAB) у вікні пів-ширини дуги
# з розмитою межею: на самому краю сила рівно `КРАЙ_ДУГИ` 0.5 (одностороння межа Φ((пів − d)/σ)). Дві межі
# сили — властивість дуги, а не число виклику: `КРАЙ_ДУГИ` — «річ несе тон» (пул, носії); `КІНЕЦЬ_ЗГАСАННЯ` — «поза без
# сумніву»: суд не звинувачує річ до нього (замість запасу 10°), добір словом (`фід_добір.описує_річ`) бере її в пул.
# Читач обирає межу (`колір_річ.у_дугах_кола`, `до_кінця_згасання`), а не число: один тризначний вердикт на вікно
# слова не тримає носіїв — слово несе тон, коли в дузі котрась його точка, а пул бере його, коли всі (2.1-Б).
# Ширина згасання — від хроми речі: «as the chroma increases, the hue becomes more specific» (MacEvoy, K-COL-11).
# Кінець згасання — кут, на якому тон речі відходить від краю дуги на сталу видиму різницю `ΔH_КРАЮ`
# (K-COL-11: «той самий тон» тримають сталою ΔH*, а не кутом), але не далі `ЗАПАС_ПРИГЛУШЕНИХ`. `ΔH_КРАЮ` — та,
# що на верху приглушених (C* 34, K-COL-06) дає рівно 10°: приглушені згасають до запасу суду, насичені —
# швидше (C* 70 — кінець 4.8°, C* 92 — 3.7°). Підлоги `СІГМА_МЕЖІ` (кінець 8.2°) тут нема: у зоні
# 0.05–0.5 насичені за краєм — переважно «інший тон»; `СІГМА_МЕЖІ` — розмиття в градусах кола (пари).
# ВИМІРЯНО ОЧИМА на речах каталогу: у насичених річ за 8–10° від краю — інший тон
# (червоне в помаранчевій ролі, блакитне в лавандовій), тож запас 10° там хибив; у приглушених ці самі 8–10° —
# той самий тон для ока через раз (бордо у винній ролі, деніми, шавлія ↔ м'ята), а ширше за 10° — інший
# (блакитне → лавандова, рожеве → беж). Тому приглушені не вужчають і не ширшають проти запасу. Відкинуто:
# ширшання ΔH* приглушених до C* 34 (рожеве заходило в бежеві ролі, бордо — в бурі), ширина кроками
# атласу Манселла на V 5 (стискає PB: блакитне заходило в лавандові ролі), ±15° кола (бурі й кемел випадали).
# КАТЕГОРІЯ ЗА КРАЄМ. Край дуги — межа ока лише там, де він — межа категорії тону: насичене
# рожеве h* 10–20 за 6–9° від краю рожевої дуги (ц351) для ока той самий тон, а рожеве h* 8 за краєм червоного вікна
# (ц30) — ні, хоча будь-якою симетричною мірою (ΔE00, CAM16-UCS, кроки Манселла) обидва від краю однаково
# (`проби/коло_ролі_рожеві_8470.py`). Тому за краєм, поки річ і центр дуги в одній категорії `МЕЖІ_КАТЕГОРІЙ`, а межа з
# боку речі підтверджена очима, згасання — запасом приглушених; через межу — за хромою, як вище.
# ДЕ ЛАМАЄТЬСЯ. Межі тону для ока — категорії (рожеве | беж, блакитне | лаванда), а тут — кут CIELAB, однаковий
# на всіх тонах і світлотах; темні (L* < 25) судяться тим самим кутом. Очима підтверджена одна межа з восьми
# (рожеве | червоне); межа фіолетове | рожеве стоїть на чотирьох речах «фіолетовий» (h* 347.7, вище центрів рожевих
# дуг ц342–345), тож рожеве за краєм цих дуг лишається «поза».
КРАЙ_ДУГИ = 0.5         # сила на самому краю дуги: від неї річ «у дузі» (несе тон, зарахована носієм)
КІНЕЦЬ_ЗГАСАННЯ = 0.05  # сила, нижче якої тон поза вікном без сумніву
ХРОМА_ПРИГЛУШЕНИХ = C["warm_neutral"][2]   # C* 34: верх смуги приглушених (K-COL-06, `палітра_схеми.ПРИГЛУШЕНО`)
ЗАПАС_ПРИГЛУШЕНИХ = 10.0   # кінець згасання приглушених, градуси CIELAB: запас суду K-PAL-03 (очима — межа)
ΔH_КРАЮ = 2.0 * ХРОМА_ПРИГЛУШЕНИХ * math.sin(math.radians(ЗАПАС_ПРИГЛУШЕНИХ) / 2.0)   # ΔH* ≈ 5.9 від краю дуги
_Z_КІНЦЯ = NormalDist().inv_cdf(1.0 - КІНЕЦЬ_ЗГАСАННЯ)   # кінець згасання — стільки σ за краєм (1.64)
# Межі категорій тону насичених (C* > 34), h* CIELAB — зі статистики назв крамниць (п.9: вікно — вжиток крамниць), раз:
# для сусідніх за медіаною слів — тон рівної помилки (частка першого слова за межею = частці другого перед нею;
# `проби/коло_ролі_категорії_8530.py`); код слів не читає (п.12). Значення — чи межу підтвердили очима: за
# краєм дуги, поки річ і центр дуги в одній категорії, а межа з боку речі ввімкнена, згасання — запасом приглушених
# (`_сила_за_краєм`); вимкнена межа лишає жорсткий край, а категорії ділить, як і ввімкнена.
МЕЖІ_КАТЕГОРІЙ = {
    23.6: True,     # рожевий (медіана 2.8) | червоний (32.0); очима «так» 10 з 10
    36.9: False,    # червоний | помаранчевий (45.4); очима хибні «так»: червоні h37–40 у помаранчевих ролях — червоні (4 з 10)
    62.5: False,    # помаранчевий | жовтий (92.2); очима хибні «так»: помаранчеве в жовтій ролі, буре й кемел в оливковій (3 з 10)
    101.8: False,   # жовтий | зелений (139.4); очима хибні «так»: жовте в лаймових ролях, олива в охристій (4 з 10)
    192.3: False,   # зелений | блакитний (267.4); очима хибні «так»: смарагд і трава в лаймових ролях; вимір фіолетового пальта h147 (2 з 10)
    276.6: False,   # блакитний | синій (289.6); очима хибні «так»: синя сукня у фіолетовому вікні (1 з 3)
    303.2: False,   # синій | фіолетовий (323.2); очима хибні «так»: фіолетові штани в синій ролі; вимір бурого светра h303 (3 з 10)
    347.7: False,   # фіолетовий | рожевий; очима хибні «так»: фуксія у фіолетових ролях, рожеве в кораловій (6 з 10)
}


_ДУГИ = {}


def _параметри_дуги(дуга):
    """(центр, пів-ширина) дуги тону (lo, hi) CIELAB з обходом 0°; кеш на дугу — добір питає ту саму дугу
    тисячі разів."""
    к = (float(дуга[0]) % 360.0, float(дуга[1]) % 360.0)
    if к not in _ДУГИ:
        пів = ((к[1] - к[0]) % 360.0) / 2.0
        _ДУГИ[к] = ((к[0] + пів) % 360.0, пів)
    return _ДУГИ[к]


def _згасання(хрома):
    """σ межі дуги тону (градуси CIELAB) для хроми C*: кінець згасання — кут сталої ΔH* `ΔH_КРАЮ` за краєм, не
    далі `ЗАПАС_ПРИГЛУШЕНИХ` (шапка розділу)."""
    кут = math.degrees(2.0 * math.asin(min(1.0, ΔH_КРАЮ / (2.0 * max(хрома, 1e-6)))))
    return min(кут, ЗАПАС_ПРИГЛУШЕНИХ) / _Z_КІНЦЯ


def _у_дузі(d, пів, σ):
    """Сила «тон за `d`° від центру дуги лежить у пів-ширині `пів`», межа розмита гаусом σ: на краю рівно 0.5.
    Межа одностороння — вікно [−пів, пів] (`у_вікні`) віднімало й дальню межу, і край давав 0.5 − Φ(−2·пів/σ),
    тож точка на краю була «поза» зрізом 0.5, а з вужчим σ — «у дузі»."""
    return _ф(пів - d, σ * math.sqrt(2.0))


def межа_за_тоном(h, ц):
    """Межа категорії тону (ключ `МЕЖІ_КАТЕГОРІЙ`), до якої тон h іде від центру дуги ц, коли обидва — в одній
    категорії; між ними межа — None (річ в іншій категорії)."""
    з = ((h - ц + 180.0) % 360.0) - 180.0
    напрям = 1.0 if з >= 0.0 else -1.0
    if any(0.0 < ((м - ц) * напрям) % 360.0 <= abs(з) for м in МЕЖІ_КАТЕГОРІЙ):
        return None
    return min(МЕЖІ_КАТЕГОРІЙ, key=lambda м: ((м - h) * напрям) % 360.0)


def _сила_за_краєм(d, пів, хрома, ширше):
    """`_у_дузі` з σ за хромою (`_згасання`); за краєм дуги в тій самій категорії тону (`ширше`) — запасом
    приглушених: межа ока там — категорія, не край дуги (шапка розділу)."""
    return _у_дузі(d, пів, ЗАПАС_ПРИГЛУШЕНИХ / _Z_КІНЦЯ if ширше and d > пів else _згасання(хрома))


def _ширше(h, ц):
    """Чи тон h за краєм дуги з центром ц згасає запасом приглушених: та сама категорія, межа з боку h ввімкнена."""
    м = межа_за_тоном(h, ц)
    return м is not None and МЕЖІ_КАТЕГОРІЙ[м]

def сила_точки_в_дузі(хрома, h, дуга):
    """`сила_в_дузі` виміряного кольору (C*, h) точкою — та сама сила без запису речі (добір питає її мільйони
    разів: `фід_добір.підходить`)."""
    ц, пів = _параметри_дуги(дуга)
    return _сила_за_краєм(кут(h, ц), пів, хрома, _ширше(h, ц))
