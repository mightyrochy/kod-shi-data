def сектор_кола(k):
    """Номер сектора 12-кольорового кола (0 — R, 1 — RO, … 11) для кута кола художника `k`."""
    return int(((k + СЕКТОР_КОЛА / 2) % 360.0) // СЕКТОР_КОЛА)


def _сектори(дуга):
    """Сектори кола, яких торкається дуга (k0, k1) кола художника, за ходом від k0 до k1."""
    if ширина(дуга) > 360.0 - СЕКТОР_КОЛА:
        return tuple(range(12))
    с, к = сектор_кола(дуга[0]), сектор_кола(дуга[1])
    сс = [с]
    while сс[-1] != к:
        сс.append((сс[-1] + 1) % 12)
    return tuple(сс)




# ── СІМ'Я ТОНУ — СЕКТОР КОЛА; СІМ'Ї НАБОРУ — ОДНА ЛІЧБА (2.14-А; п.18) ───────────────────
# ПРОБЛЕМА. Три лічби «скільки сімей тону» над тими самими речима, і жодна — на колі: K-COMP-03 — дуги `FAMILIES`
# CIELAB без злиття (h44 і h46, 2° кола, — дві сім'ї, soft «понад ліміт» → ремонт); K-PAL-07 — дуги
# `palettes.СІМ_Ї` з прогалинами (бірюза h200 і нейві h285, 57° кола, — обидві «синя»; h245 мовчки випадав);
# сміливість (`вердикт_моделі.ознаки_сміливості`) — шість секторів по 60° CIELAB (h175/200/250 — три «сім'ї» на
# 41° кола, h30/58/95 — дві на 111°).
# ПРАВИЛО. Сім'я тону — сектор кола художника: дуга завширшки з крок 12-кольорового кола (`СЕКТОР_КОЛА`, 30°).
# Сімей у наборі — найменше число таких дуг, що вміщають тони всіх речей; дуга ковзає, а не стоїть на сітці
# R 0°, RO 30°…: нерухома сітка розводила 2° кола через межу і, навпаки, тримала разом 29° в одному секторі.
# Річ належить дузі, коли вміщається в неї вікном із плавною межею (`у_вікні`, σ `СІГМА_МЕЖІ`,
# зріз 0.5). Від порядку речей лічба не залежить (3350: «за першим представником» — 2/2/1/1/2/2 у шести порядках).
# ВИМІРЯНО ОЧИМА (образи з кольорів каталогу): нерухомі 12 секторів зі злиттям `same_hue`
# помилились у 3 з 10 — ділили блакитне й нейві (29° кола), коричневе й червоне (17°); ковзна дуга — у 2 з 20, обидва
# рази світле й темне коричневе (34° і 53° кола), а рожеве й червоне (35°), винне й сливове (33°) лишає різними
# сім'ями, як і око. Назва групи — код сектора (`внутрішня_мова` «hue_sector») середини її дуги.
# ДЕ ЛАМАЄТЬСЯ. Межа 30° тверда для двох вимірів (зріз 0.5 вікна точно на ній): 29° — одна сім'я, 31° — дві. Тон
# не знає світлоти: буре — темне помаранчеве, рожеве — світле червоне, і сім'ю за світлотою лічба не ділить. Вікно
# слова, ширше за дугу сім'ї, — сім'я невідома, не своя й не чужа.
def вміщається_в_сім_ю(розмах):
    """Чи тони, що займають `розмах`° кола (0…360, хід від першого тону), вміщаються в одну дугу сім'ї (вікно
    `СЕКТОР_КОЛА`, плавна межа). Розмах — не відстань: понад 180° вона не згортається в коротшу дугу."""
    return розмах < 180.0 and у_вікні(розмах, (0.0, СЕКТОР_КОЛА, False), СІГМА_МЕЖІ) >= 0.5


# СІМ'Я = ТОН + СВІТЛОТА: БУРЕ (2.14-Б). Буре — темне й приглушене помаранчеве, і око кладе шоколад, каштан,
# мідь і кемел в одну сім'ю, хоч на колі вони розходяться на 34–90° (коло розтягує помаранчеву смугу вчетверо, а
# тон темних ще й дрейфує: Munsell 5YR — 28° кола на V2 і 65° на V8). Межі — з корпусу: слова крамниць у назвах
# виміряних речей каталогу (15 830). Темні L* < 30 з C* < 25 і тоном 18–28° — «коричнева» 48 проти «червона» 9
# (на 28–45° — 188 : 0), тож нижній край — межа 6R ISCC-NBS L* − 3 (`ДУГА_БУРОГО`), а не 28° `темне_буре`;
# нижче 18° — бордо; ті самі темні з C* 25–45 — «червона» 23 : 0, тож хромним бурим край — теплий коридор (45°).
# Світлі L* 56–68 з C* 34–42 і тоном 55–80° — «беж / кемел» 13 (решта без слова): кемел у межах світлоти;
# хрома — до 45: «карамель» C* 42 і «охра» 43 бурі, «теракота» 47 — уже ні; далі — помаранчеве й гірчичне. Верхній край тону — кінець вікон «коричневий» і «кемел» `ЛЕКСИКОН` (95°).
# Буре зводить лише розведених бурих — в окрему буру сім'ю (злиття в змішану групу клало мідь до малинового);
# одне буре чи бурі разом від сусідів по колу (бордо, червоне, помаранчеве) не відриваються.
БУРЕ_СІМ_Ї = dict(L_темного=30.0, C_темного=25.0, h_темного=18.0, L=68.0, C=45.0, h_до=95.0)


def буре_сім_я(L, Cc, h):
    """Чи точка виміру — буре сім'ї тону (`БУРЕ_СІМ_Ї`): темне приглушене від межі 6R ISCC-NBS (L* − 3, не нижче
    бордо) чи хромне до кемелу від теплого коридору; тон до кінця вікон «коричневий» / «кемел»."""
    б, від = БУРЕ_СІМ_Ї, L + ДУГА_БУРОГО[0]
    if L < б["L_темного"] and Cc < б["C_темного"]:
        return max(від, б["h_темного"]) <= h < б["h_до"]
    return L < б["L"] and Cc <= б["C"] and max(від, C["warm_neutral"][0]) <= h < б["h_до"]


def групи_сімей(дуги, бурі=()):
    """(групи, невідомі) — сім'ї тону над дугами кола художника: `дуги` — {i: (k0, k1)}; групи — [(сектор, [i, …]), …]
    у порядку кола, де сектор — номер `сектор_кола` середини дуги групи; невідомі — i дуг, ширших за дугу сім'ї.
    `бурі` — i виміряних бурих (`буре_сім_я`): ті з них, що розведені покриттям, виходять зі своїх груп в одну
    буру; буре, що не розведене, лишається з сусідами по колу. Від порядку i лічба не залежить."""
    зз = дуги
    невідомі = sorted(i for i, к in зз.items() if not вміщається_в_сім_ю(ширина(к)))
    бурі = set(бурі) - set(невідомі)
    певні = {i: к for i, к in зз.items() if i not in невідомі}

    def звести_бурих(групи):
        з_бурими = [г for г in групи if бурі & set(г)]
        if len(з_бурими) < 2:
            return групи
        разом = [i for г in з_бурими for i in г if i in бурі]
        розмах = lambda с: max((певні[i][0] - певні[с][0]) % 360.0 + ширина(певні[i]) for i in разом)
        с0 = min(разом, key=lambda с: (розмах(с), с))   # початок — той, з якого розмах найменший (назва — його середина)
        решта = [[i for i in г if i not in бурі] for г in групи]
        return [г for г in решта if г] + [sorted(разом, key=lambda i: ((певні[i][0] - певні[с0][0]) % 360.0, i))]

    найкраще = None
    for старт in певні:   # коло без початку: найменше покриття — з котроїсь речі як першої
        зсув = lambda i: (певні[i][0] - певні[старт][0]) % 360.0
        черга, групи = sorted(певні, key=lambda i: (зсув(i), i)), []
        while черга:
            s = зсув(черга[0])
            група = [i for i in черга if зсув(i) >= s and вміщається_в_сім_ю(зсув(i) + ширина(певні[i]) - s)]
            групи.append(група)
            черга = [i for i in черга if i not in група]
        групи = звести_бурих(групи)
        if найкраще is None or len(групи) < len(найкраще):
            найкраще = групи
    def назва(гг):
        """Номер сектора середини дуги групи: від першого тону до найдальшого кінця."""
        к0 = певні[гг[0]][0]
        к1 = max((к0 + (певні[i][0] - к0) % 360.0 + ширина(певні[i])) for i in гг)
        return сектор_кола((к0 + к1) / 2.0)
    групи = sorted(((назва(гг), sorted(гг)) for гг in найкраще or ()), key=lambda x: (x[0], x[1]))
    return групи, невідомі
