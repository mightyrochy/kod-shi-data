# ── КОЛО ХУДОЖНИКА: ДРУГА СТОРОНА КОМПЛЕМЕНТУ (K-COL-03 §4, аудит/ПРОДУКТ.md п.18) ──────
# Корпус називає комплементарні пари за колом художника — «burgundy + pine, camel +
# navy, teal + copper», — а протилежність у CIELAB (h+180) розходилась із ними на 48°,
# 28° і 46° (`проби/комплемент_дуги_1043.py`): бордо діставало пастельну бірюзу, а не
# хвою. Тут кут CIELAB переводиться на коло художника, там +180°, і назад. Опори кола —
# ПАРИ на місцях 12-кольорового кола (R 0°, RO 30°, O 60°, YO 90°, G 180°, BG 210°,
# B 240°, BV 270°); між опорами — лінійно, тож відображення неперервне й монотонне.
# Набір опор замкнений щодо +180° (кожна опора має пару навпроти), тож друга сторона
# від місць опор не залежить: пара опор переходить у пару.
# ЗВІДКИ ТОНИ ОПОР. Три пари корпусу — бордо R ↔ хвоя G, мідь RO ↔ тіл BG, кемел YO ↔
# темно-синій BV — тони підібрано перебором так, щоб і типові зразки слів корпусу, і
# медіани тону речей каталогу зі словом кольору (п.9) сходились у межах 10°. Четверта
# пара — канонічний комплемент кола O ↔ B: B — медіана тону речей зі словом «блакитний»
# (h253.9, n=509; п.9: вікно слова — вжиток крамниць), O — її пара навпроти, на лінії
# мідь–кемел (h61.5 — там, куди 60° кола ставить лінійний відрізок 30°–90°), тож теплий
# бік лишається лінійним, без нової опори-слова. «Коричневий» (h58) за 4° від міді дав
# би лупу 7.5° кола на 1° тону: карі очі й волосся (h50–60) хитали б третини схем.
# МІСЦЯ ОПОР ДЛЯ ТРЕТИН. Для кроків 120°/30°/150° місця вже НЕ байдужі.
# Доти мідь і тіл стояли посередині (45°/225°), а пари O ↔ B не було: відрізок тіл–
# темно-синій (h188–282) стискав 94° CIELAB у 45° кола, блакитний h254 стояв на 257°, і
# тріада від бордо діставала синьо-бірюзовий h202 замість блакитного (взірець власниці
# «оливковий жакет, блакитна сорочка, бордова спідниця» — відхил 52°). Тепер мідь і тіл
# — на своїх місцях RO/BG, блакитний — на B: найбільший відхил взірця 19° з кожного з
# трьох якорів (суд K-PAL-03 приймає з усіх трьох; доти з двох), комплементи медіан
# каталогу — 5/4/7° замість 5/8/9° (`проби/коло3_опори.py`). ДЕ ЛАМАЄТЬСЯ: опори —
# слова, не вимір (T3); між опорами — лінійна інтерполяція, а не виміряне сприйняття;
# «синій» каталогу (h277) — біля темно-синього, на 265°, а не на B 240°: у вжитку
# крамниць «синій» темніший і фіолетовіший за синій кола художника.
# Ціна: «помаранчевий» (h51) і «коричневий» (h58) каталогу стали на 27° і 46° кола (доти
# 41° і 57°) — ближче до RO, ніж до O: мідь RO і помаранч у вжитку крамниць — один тон.
_КОЛО = ((25.0, 0.0), (54.0, 30.0), (61.5, 60.0), (69.0, 90.0), (157.0, 180.0), (188.0, 210.0),
         (253.9, 240.0), (282.0, 270.0))

def _лінійно(x, вузли):
    """Кусково-лінійне відображення кута `x` за вузлами [(від, до)] по колу 0–360°:
    `від` зростає, останній відрізок замикається на перший через 360°."""
    x = x % 360.0
    for (x0, y0), (x1, y1) in zip(вузли, вузли[1:] + ((вузли[0][0] + 360.0, вузли[0][1] + 360.0),)):
        xx = x if x >= x0 else x + 360.0
        if x0 <= xx <= x1:
            return (y0 + (xx - x0) * (y1 - y0) / (x1 - x0)) % 360.0
    raise ValueError("кут %r поза вузлами кола" % (x,))

def у_коло_художника(h):
    """Кут тону CIELAB `h` → кут на колі художника (R 0°, G 180°)."""
    return _лінійно(h, _КОЛО)

def з_кола_художника(a):
    """Кут на колі художника → кут тону CIELAB (обернене до `у_коло_художника`)."""
    вузли = sorted((y, x) for x, y in _КОЛО)
    return round(_лінійно(a, tuple(вузли)), 1)

# УСІ ВІДНОШЕННЯ СХЕМ — НА ТОМУ САМОМУ КОЛІ (КОЛО-2; аудит/ПРОДУКТ.md п.18). Доти коло
# художника несло лише комплемент, а тріада (+120°/+240°), аналогова (+30°/+55°) і розщеплена
# (±150°) крокували кутами CIELAB — дві геометрії для одного «відношення тону». Тепер кожен
# зсув відношення — кроком по колу художника (`зсув_на_колі`), а ширина дуги навколо центру
# лишається в CIELAB, як у комплементу з КОЛО-1: вона каже, наскільки тон речі може відійти
# від цілі, і це відстань сприйняття, не відношення. Світлота й хрома — у CIELAB, як були.
# Для кроків, не кратних 180°, місця опор на колі (`_КОЛО`, другий стовпець) не байдужі —
# вони стоять на місцях 12-кольорового кола (коментар над `_КОЛО`).
def зсув_на_колі(h, кут):
    """Тон CIELAB, що стоїть на `кут` градусів від `h` на колі художника (знак — напрям)."""
    return з_кола_художника(у_коло_художника(h) + float(кут))

def доповнення(h):
    """Друга сторона комплементу для тону CIELAB `h`: +180° на колі художника, назад у
    CIELAB. Єдине місце, де код будує протилежну сторону (схеми, спектри рис, палітра)."""
    return зсув_на_колі(h, 180.0)

# ТЕПЛЕ ↔ ХОЛОДНЕ — ОДНЕ ВИЗНАЧЕННЯ (2.14-А; аудит/ПРОДУКТ.md п.18: «тепле ↔ холодне — одним визначенням
# за досвідом практиків»). Доти три конвенції: знак b* (основи, фішки, ґратка), cos(h − 60°) CIELAB (риси) і
# cos(k − 30°) на колі художника (Itten, `колір_відношення`). Практики корпусу ставлять тепло на жовто-синю вісь:
# «warm red = tomato/brick/coral vs cool red = raspberry/berry; warm blue = teal/turquoise/petrol vs cool blue =
# cobalt/periwinkle/navy» (тема-2, K-PAL-01: Sci\ART, Lamport, JPCA) і R-COL-16 (b* речі проти очей, Perrett).
# Виміряно на версіях `palettes.СІМ_Ї`: b*/C* ставить теплу версію теплішою за холодну в усіх шести сім'ях із
# двома версіями; Itten на колі і cos(h − 60°) — у п'яти, бо синя в них навпаки (бірюза — холодний полюс Іттена,
# кобальт тепліший). Тому тепло — b*/C*, тобто sin h. ДЕ ЛАМАЄТЬСЯ: вісь абсолютна, а версія сім'ї — відносна
# (холодна зелена h170 має b* > 0); підпис версії бере дугу сім'ї, а не знак цієї осі.
def тепло(h):
    """Теплота тону CIELAB `h`, −1…1: b*/C* = sin h — жовтий (h 90°) найтепліший, синій (270°) найхолодніший,
    червоний і ціан (0°/180°) — межа. None — тону нема (теплота не виміряна, не нуль)."""
    return None if h is None else math.sin(math.radians(h))

def центри_відношення(h, rel):
    """Центри дуг відношення `rel` (з `RELATIONS`) від тону `h`: кожен зсув — на колі
    художника (`зсув_на_колі`), комплемент — `доповнення`; нульовий зсув — сам `h`."""
    off = RELATIONS[rel][0]
    if off == 180:
        return [доповнення(h)]
    if not off:
        return [h % 360]
    return [зсув_на_колі(h, off), зсув_на_колі(h, -off)]

def дуга_кола(h, пів):
    """Дуга тону CIELAB (від, до) — образ дуги кола художника з центром у тоні CIELAB `h` і пів-шириною
    `пів`° кола (КОЛІР-СХЕМИ, п.18). Ширина дуги — на колі, як і її зсув (`зсув_на_колі`): ±15°
    кола — той самий сектор у будь-якому тоні, а ±15° CIELAB — це ±7° кола в синіх і до ±38° у бурих. Силу
    членства в такій дузі судить `колір_відношення.сила_в_дузі`. Споживач — сім'я очей
    (`palettes.дуга_очей`) і ролі схем (`palettes.дуга`, 2.14-Б); спектри рис лишились кутами CIELAB."""
    return (з_кола_художника(у_коло_художника(h) - float(пів)) % 360.0,
            з_кола_художника(у_коло_художника(h) + float(пів)) % 360.0)


# ═══════ 2. ДУГИ ТОНУ — ГЕОМЕТРІЯ (одна на всіх читачів) ═══════
# Дуга — пара (від, до) кутів тону (CIELAB чи коло художника: геометрія та сама), з переходом через 0° (від > до).
# Край входить у дугу з обох боків: шов між сусідніми дугами — спільне число, і тон на ньому належить обом
# (хто з двох виграє — правило нічиєї сім'ї нижче, а не `<` проти `<=` в читачеві).
def arc(c, half):
    """Дуга (c − half, c + half) по модулю 360."""
    return розширити_дугу((c, c), half)


def в_дузі(h, дуга):
    """Чи тон h лежить на дузі (від, до), краї входять; дуга з переходом через 0° (від > до) — теж."""
    lo, hi = дуга
    if hi - lo >= 360.0:
        return True
    return (lo <= h <= hi) if lo <= hi else (h >= lo or h <= hi)


def хід(a, b):
    """Скільки градусів іти від тону `a` до тону `b` за годинниковою стрілкою кола, 0…360 (b = a → 0)."""
    return (b - a) % 360.0


def зсунути(h, на):
    """Тон `h`, зсунутий на `на` градусів за годинниковою стрілкою кола (від'ємне — проти), по модулю 360."""
    return (h + на) % 360.0


def різниця_знакова(a, b):
    """Знакова різниця тонів `a − b` коротшим шляхом по колу, [−180, 180): додатна, коли `a` далі за `b` за годинниковою."""
    return (a - b + 180.0) % 360.0 - 180.0


def ширина(дуга):
    """Ширина дуги (від, до) у градусах: хід від `від` до `до` за годинниковою стрілкою кола. ДУГА (x, x) — ТОЧКА
    (ширина 0: вимір, центр сім'ї), так її читають і `в_дузі`, і `розкид_дуг`; усе коло — дуга (x, x + 360), ширина 360.
    Два значення одного запису (точка в одному читачеві, усе коло в іншому) ховали, що саме прийшло."""
    return 360.0 if дуга[1] - дуга[0] >= 360.0 else хід(дуга[0], дуга[1])


def розширити_дугу(дуга, на, вперед=None):
    """Дуга (від − на, до + вперед) по модулю 360; `вперед` не задано — тоді `на` з обох боків (від'ємне звужує)."""
    return ((дуга[0] - на) % 360.0, (дуга[1] + (на if вперед is None else вперед)) % 360.0)


def дуга_всередині(да, дб):
    """Чи дуга `да` цілком лежить на дузі `дб` (краї входять; допуск 1e-9° на округлення країв)."""
    return в_дузі(да[0], дб) and хід(дб[0], да[0]) + ширина(да) <= ширина(дб) + 1e-9


def середина(дуга):
    """Тон середини дуги (від, до) — коротким шляхом через 0°."""
    return (дуга[0] + ширина(дуга) / 2.0) % 360.0


def відстань_до_дуги(h, дуга):
    """Кут (°) від тону h до найближчого краю дуги, коротшим шляхом по колу."""
    return min(кут(h, x) for x in дуга)


def кут(a, b):
    """Коротша кутова відстань між двома тонами, 0…180°."""
    d = abs(a - b) % 360.0
    return min(d, 360.0 - d)


def розкид_дуг(да, дб):
    """(мін, макс) кутової відстані тонів над двома дугами тону (CIELAB чи кола художника; вимір —
    дуга (h, h)): мінімум 0, коли дуги перетинаються, максимум 180, коли дуга однієї заходить навпроти
    другої, інакше обидва — на кінцях дуг. Дуга None (без тону) — (0, 180)."""
    if да is None or дб is None:
        return (0.0, 180.0)
    if да[0] == да[1] and дб[0] == дб[1]:   # дві точки (вимір чи центр сім'ї): обидва кінці — їхня відстань
        d = кут(да[0], дб[0])
        return (d, d)
    кінці = [(x, y) for x in да for y in дб]
    перетин = any(в_дузі(k, дб) for k in да) or any(в_дузі(k, да) for k in дб)
    навпроти = ((дб[0] + 180.0) % 360.0, (дб[1] + 180.0) % 360.0)
    протилежні = any(в_дузі(k, навпроти) for k in да) or any(в_дузі(k, да) for k in навпроти)
    return (0.0 if перетин else min(кут(x, y) for x, y in кінці),
            180.0 if протилежні else max(кут(x, y) for x, y in кінці))

# ═══════ 3. МЕЖІ: СТАЛІ, ВІКНА ВІДНОШЕНЬ, РОЗМИТТЯ КРАЇВ ═══════
СІГМА_МЕЖІ = 5.0        # розмиття межі категорії тону, градуси кола художника
ДУГА_БУРОГО = (-3.0, C["warm_neutral"][1])  # тони бурого CIELAB у темних: від L* − 3 (межа 6R ISCC-NBS) до кінця теплого коридору
ТЕПЛИЙ_ПОЛЮС = 90.0     # найтепліший тон CIELAB — жовтий кінець осі b* (`colorspace.тепло`, 2.14-А), протилежний — синій 270°

# Межі кола художника, на яких стоять вікна тону (`колір_відношення` й `колір_річ`
# читають їх звідси, тож ланцюг імпорту — читачі → цей модуль, не навпаки).
# ДУГА_ВІДЛУННЯ — той самий голос тону: пів сектора 12-кольорового кола (Р2а).
ДУГА_ВІДЛУННЯ = 15.0
СЕКТОР_КОЛА = 30.0      # крок 12-кольорового кола художника (R 0°, RO 30°, O 60°, …)
_ДВ, _СК = ДУГА_ВІДЛУННЯ, СЕКТОР_КОЛА
_тр, _рз, _кп = RELATIONS["triadic"], RELATIONS["split"], RELATIONS["complementary"]
# Вікна відстані тонів на колі: (від, до, нижня межа відкрита). Межі — `колір_річ.відношення`
# (Р2а, K-PAL-05, `RELATIONS`), нові — аналогова (1–2 сектори) і квадрат (90 ± пів сектора).
ВІКНА_ТОНУ = {
    "same_hue": (0.0, _ДВ, False),                          # той самий сектор: відлуння, повтор
    "adjacent": (_ДВ, _ДВ + _СК, True),                     # сусідній сектор (K-PAL-04)
    "near_hue": (0.0, _ДВ + _СК, False),                    # той самий чи сусідній (K-COL-02)
    "analogous": (_ДВ, _ДВ + 2 * _СК, True),                # аналогова: 1–2 сектори поруч
    "square": (90.0 - _ДВ, 90.0 + _ДВ, False),              # квадрат — пара тетради
    "triadic": (_тр[0] - _тр[1], _тр[0] + _тр[1], False),
    "split": (_рз[0] - _рз[1], _рз[0] + _рз[1], False),
    "complementary": (_кп[0] - _кп[1], 180.0, False),       # K-COL-03 §4, K-PAL-05: від 150°
}
# Вікна різниці тону ΔH* для ближніх класів (K-COL-11): (зовнішня межа, внутрішній клас, віднімається) —
# той самий тон |ΔH*| ≤ 3 (практики: пів кроку атласу Манселла /8, сторінки Nearly Neutrals /4, назви ISCC-NBS
# /2 і /1 — ±2…3.3); ближній ≤ 9 і аналоговий ≤ 15 — ті самі пропорції 1 : 3 : 5, що 15 : 45 : 75° кола.
# Сусідній і аналоговий — зовнішнє вікно мінус «той самий» (кільце навколо нуля). Класу поза словником
# ΔH* не судить (далекі відношення — лише коло); `ВІКНА_ΔH = {}` — кодування Р2а без поправки практиків.
ВІКНА_ΔH = {
    "same_hue": (3.0, None),
    "near_hue": (9.0, None),
    "adjacent": (9.0, "same_hue"),
    "analogous": (15.0, "same_hue"),
}
СІГМА_ΔH = 1.0          # розмиття межі ΔH* — та сама частка пів-ширини, що СІГМА_МЕЖІ / ДУГА_ВІДЛУННЯ (5 / 15)
МЕЖА_БЛИЗЬКИХ = 90.0    # ближні класи за ΔH* — не далі чверті кола (Moon–Spencer ±43°, PCCS проміжний 60–105°)

_ЕРФ_НАСИЧЕННЯ = 6.0   # erf(6) = 1 − 2·10⁻¹⁷: далі за 6·s від точки нормальний розподіл не відрізняється від 0 чи 1


def _ф(x, s):
    """Нормальна функція розподілу в точці x при масштабі s = σ·√2."""
    return 0.5 * (1.0 + math.erf(x / s))


def у_вікні(d, вікно, сигма):
    """Імовірність, що справжня відстань тонів на колі лежить у `вікно` (від, до, відкрита), коли
    виміряна — d (0…180°), а знак і зсув різниці розмиті гаусом σ (σ = 0 — тверда межа).

    Чому так: різниця тонів зі знаком δ ~ N(d, σ), а відстань — |δ|, згорнута на колі, тож вікну
    [a, b] відповідають відрізки [a, b] і [−b, −a] з кроком 360°; при σ → ∞ сила прямує до частки
    кола під вікном (той самий сектор — 1/12)."""
    a, b, відкрита = вікно
    if сигма <= 0.0:
        return 1.0 if ((d > a) if відкрита else (d >= a)) and d <= b else 0.0
    s, p = сигма * math.sqrt(2.0), 0.0
    for м in (-720.0, -360.0, 0.0, 360.0, 720.0):
        # відрізки [a, b] і [−b, −a] далі за _ЕРФ_НАСИЧЕННЯ·s від d дають 0 точно до double (erf уже ±1) — зсув пропущено
        if м - d - b > _ЕРФ_НАСИЧЕННЯ * s or м - d + b < -_ЕРФ_НАСИЧЕННЯ * s: continue
        if a == 0.0:   # відрізки зливаються в [−b, b]: середні члени скорочуються
            p += _ф(b + м - d, s) - _ф(-b + м - d, s)
        else:
            p += _ф(b + м - d, s) - _ф(a + м - d, s) + _ф(-a + м - d, s) - _ф(-b + м - d, s)
    return min(1.0, max(0.0, p))


def _у_вікні_меж(р, вікно, сигма):
    """(мін, макс) `у_вікні` для відстані з інтервалу р = (мін, макс): сила одногорба з вершиною в
    центрі вікна (0 — для вікна від нуля, 180 — для вікна до 180), тож мінімум — на кінці інтервалу,
    максимум — у найближчій до центру точці."""
    a, b, _ = вікно
    ц = 0.0 if a == 0.0 else 180.0 if b == 180.0 else (a + b) / 2.0
    return (min(у_вікні(р[0], вікно, сигма), у_вікні(р[1], вікно, сигма)),
            у_вікні(min(max(ц, р[0]), р[1]), вікно, сигма))


# ── ДУГА ТОНУ — ВІКНО З СИЛОЮ, ЩО ЗГАСАЄ ДО КРАЇВ ───────────────────────────────────────────────────
# Одна сила для всіх дуг тону: відстань тону речі до центру дуги (кут CIELAB) у вікні пів-ширини дуги
# з розмитою межею: на самому краю сила рівно `КРАЙ_ДУГИ` 0.5 (одностороння межа Φ((пів − d)/σ)). Дві межі
# сили — властивість дуги, а не число виклику: `КРАЙ_ДУГИ` — «річ несе тон» (пул, носії); `КІНЕЦЬ_ЗГАСАННЯ` — «поза без
# сумніву»: суд не звинувачує річ до нього (замість запасу 10°), добір словом (`фід_добір.описує_річ`) бере її в пул.
# Читач обирає межу (`колір_річ.у_дугах_кола`, `до_кінця_згасання`), а не число: один тризначний вердикт на вікно
# слова не тримає носіїв — слово несе тон, коли в дузі котрась його точка, а пул бере його, коли всі (2.1-Б).
# Ширина згасання — від хроми речі: «as the chroma increases, the hue becomes more specific» (MacEvoy, K-COL-11).
# Кінець згасання — кут, на якому тон речі відходить від краю дуги на сталу видиму різницю `ΔH_КРАЮ`
# (K-COL-11: «той самий тон» тримають сталою ΔH*, а не кутом), але не далі `ЗАПАС_ПРИГЛУШЕНИХ`. `ΔH_КРАЮ` — та,
# що на верху приглушених (C* 34, K-COL-06) дає рівно 10°: приглушені згасають до запасу суду, насичені —
# швидше (C* 70 — кінець 4.8°, C* 92 — 3.7°). Підлоги `СІГМА_МЕЖІ` (кінець 8.2°) тут нема: у зоні
# 0.05–0.5 насичені за краєм — переважно «інший тон»; `СІГМА_МЕЖІ` — розмиття в градусах кола (пари).
# ВИМІРЯНО ОЧИМА на речах каталогу: у насичених річ за 8–10° від краю — інший тон
# (червоне в помаранчевій ролі, блакитне в лавандовій), тож запас 10° там хибив; у приглушених ці самі 8–10° —
# той самий тон для ока через раз (бордо у винній ролі, деніми, шавлія ↔ м'ята), а ширше за 10° — інший
# (блакитне → лавандова, рожеве → беж). Тому приглушені не вужчають і не ширшають проти запасу. Відкинуто:
# ширшання ΔH* приглушених до C* 34 (рожеве заходило в бежеві ролі, бордо — в бурі), ширина кроками
# атласу Манселла на V 5 (стискає PB: блакитне заходило в лавандові ролі), ±15° кола (бурі й кемел випадали).
# КАТЕГОРІЯ ЗА КРАЄМ. Край дуги — межа ока лише там, де він — межа категорії тону: насичене
# рожеве h* 10–20 за 6–9° від краю рожевої дуги (ц351) для ока той самий тон, а рожеве h* 8 за краєм червоного вікна
# (ц30) — ні, хоча будь-якою симетричною мірою (ΔE00, CAM16-UCS, кроки Манселла) обидва від краю однаково
# (`проби/коло_ролі_рожеві_8470.py`). Тому за краєм, поки річ і центр дуги в одній категорії `МЕЖІ_КАТЕГОРІЙ`, а межа з
# боку речі підтверджена очима, згасання — запасом приглушених; через межу — за хромою, як вище.
# ДЕ ЛАМАЄТЬСЯ. Межі тону для ока — категорії (рожеве | беж, блакитне | лаванда), а тут — кут CIELAB, однаковий
# на всіх тонах і світлотах; темні (L* < 25) судяться тим самим кутом. Очима підтверджена одна межа з восьми
# (рожеве | червоне); межа фіолетове | рожеве стоїть на чотирьох речах «фіолетовий» (h* 347.7, вище центрів рожевих
# дуг ц342–345), тож рожеве за краєм цих дуг лишається «поза».
КРАЙ_ДУГИ = 0.5         # сила на самому краю дуги: від неї річ «у дузі» (несе тон, зарахована носієм)
КІНЕЦЬ_ЗГАСАННЯ = 0.05  # сила, нижче якої тон поза вікном без сумніву
ХРОМА_ПРИГЛУШЕНИХ = C["warm_neutral"][2]   # C* 34: верх смуги приглушених (K-COL-06, `палітра_схеми.ПРИГЛУШЕНО`)
ЗАПАС_ПРИГЛУШЕНИХ = 10.0   # кінець згасання приглушених, градуси CIELAB: запас суду K-PAL-03 (очима — межа)
ΔH_КРАЮ = 2.0 * ХРОМА_ПРИГЛУШЕНИХ * math.sin(math.radians(ЗАПАС_ПРИГЛУШЕНИХ) / 2.0)   # ΔH* ≈ 5.9 від краю дуги
_Z_КІНЦЯ = NormalDist().inv_cdf(1.0 - КІНЕЦЬ_ЗГАСАННЯ)   # кінець згасання — стільки σ за краєм (1.64)
# Межі категорій тону насичених (C* > 34), h* CIELAB — зі статистики назв крамниць (п.9: вікно — вжиток крамниць), раз:
# для сусідніх за медіаною слів — тон рівної помилки (частка першого слова за межею = частці другого перед нею;
# `проби/коло_ролі_категорії_8530.py`); код слів не читає (п.12). Значення — чи межу підтвердили очима: за
# краєм дуги, поки річ і центр дуги в одній категорії, а межа з боку речі ввімкнена, згасання — запасом приглушених
# (`_сила_за_краєм`); вимкнена межа лишає жорсткий край, а категорії ділить, як і ввімкнена.
МЕЖІ_КАТЕГОРІЙ = {
    23.6: True,     # рожевий (медіана 2.8) | червоний (32.0); очима «так» 10 з 10
    36.9: False,    # червоний | помаранчевий (45.4); очима хибні «так»: червоні h37–40 у помаранчевих ролях — червоні (4 з 10)
    62.5: False,    # помаранчевий | жовтий (92.2); очима хибні «так»: помаранчеве в жовтій ролі, буре й кемел в оливковій (3 з 10)
    101.8: False,   # жовтий | зелений (139.4); очима хибні «так»: жовте в лаймових ролях, олива в охристій (4 з 10)
    192.3: False,   # зелений | блакитний (267.4); очима хибні «так»: смарагд і трава в лаймових ролях; вимір фіолетового пальта h147 (2 з 10)
    276.6: False,   # блакитний | синій (289.6); очима хибні «так»: синя сукня у фіолетовому вікні (1 з 3)
    303.2: False,   # синій | фіолетовий (323.2); очима хибні «так»: фіолетові штани в синій ролі; вимір бурого светра h303 (3 з 10)
    347.7: False,   # фіолетовий | рожевий; очима хибні «так»: фуксія у фіолетових ролях, рожеве в кораловій (6 з 10)
}


_ДУГИ = {}


def _параметри_дуги(дуга):
    """(центр, пів-ширина) дуги тону (lo, hi) CIELAB з обходом 0°; кеш на дугу — добір питає ту саму дугу
    тисячі разів."""
    к = (float(дуга[0]) % 360.0, float(дуга[1]) % 360.0)
    if к not in _ДУГИ:
        пів = ((к[1] - к[0]) % 360.0) / 2.0
        _ДУГИ[к] = ((к[0] + пів) % 360.0, пів)
    return _ДУГИ[к]


def _згасання(хрома):
    """σ межі дуги тону (градуси CIELAB) для хроми C*: кінець згасання — кут сталої ΔH* `ΔH_КРАЮ` за краєм, не
    далі `ЗАПАС_ПРИГЛУШЕНИХ` (шапка розділу)."""
    кут = math.degrees(2.0 * math.asin(min(1.0, ΔH_КРАЮ / (2.0 * max(хрома, 1e-6)))))
    return min(кут, ЗАПАС_ПРИГЛУШЕНИХ) / _Z_КІНЦЯ


def _у_дузі(d, пів, σ):
    """Сила «тон за `d`° від центру дуги лежить у пів-ширині `пів`», межа розмита гаусом σ: на краю рівно 0.5.
    Межа одностороння — вікно [−пів, пів] (`у_вікні`) віднімало й дальню межу, і край давав 0.5 − Φ(−2·пів/σ),
    тож точка на краю була «поза» зрізом 0.5, а з вужчим σ — «у дузі»."""
    return _ф(пів - d, σ * math.sqrt(2.0))


def межа_за_тоном(h, ц):
    """Межа категорії тону (ключ `МЕЖІ_КАТЕГОРІЙ`), до якої тон h іде від центру дуги ц, коли обидва — в одній
    категорії; між ними межа — None (річ в іншій категорії)."""
    з = ((h - ц + 180.0) % 360.0) - 180.0
    напрям = 1.0 if з >= 0.0 else -1.0
    if any(0.0 < ((м - ц) * напрям) % 360.0 <= abs(з) for м in МЕЖІ_КАТЕГОРІЙ):
        return None
    return min(МЕЖІ_КАТЕГОРІЙ, key=lambda м: ((м - h) * напрям) % 360.0)


def _сила_за_краєм(d, пів, хрома, ширше):
    """`_у_дузі` з σ за хромою (`_згасання`); за краєм дуги в тій самій категорії тону (`ширше`) — запасом
    приглушених: межа ока там — категорія, не край дуги (шапка розділу)."""
    return _у_дузі(d, пів, ЗАПАС_ПРИГЛУШЕНИХ / _Z_КІНЦЯ if ширше and d > пів else _згасання(хрома))


def _ширше(h, ц):
    """Чи тон h за краєм дуги з центром ц згасає запасом приглушених: та сама категорія, межа з боку h ввімкнена."""
    м = межа_за_тоном(h, ц)
    return м is not None and МЕЖІ_КАТЕГОРІЙ[м]

def сила_точки_в_дузі(хрома, h, дуга):
    """`сила_в_дузі` виміряного кольору (C*, h) точкою — та сама сила без запису речі (добір питає її мільйони
    разів: `фід_добір.підходить`)."""
    ц, пів = _параметри_дуги(дуга)
    return _сила_за_краєм(кут(h, ц), пів, хрома, _ширше(h, ц))


