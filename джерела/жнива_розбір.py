import verify as V
from жнива_реєстр import КРОЇ, МАТЕРІАЛИ, ВІЗЕРУНКИ, ДОВЖИНИ, ДОВЖИНА_В_РІВЕНЬ

# ── НОРМАЛІЗАЦІЯ ────────────────────────────────────────────────────────────
def _число(v, lo, hi, ціле=False):
    """Число моделі в межах [lo, hi]: ціле або з двома знаками; не число — None."""
    try:
        x = float(v)
    except (TypeError, ValueError):
        return None
    x = min(hi, max(lo, x))
    return int(round(x)) if ціле else round(x, 2)


def _слово(v, дозволені, розбирач=None):
    """Слово моделі → слово словника правил; чого нема в словнику — null."""
    с = str(v or "").strip().lower() or None
    if not с:
        return None
    if с in дозволені:
        return с
    if розбирач:
        с2 = розбирач(с)
        return с2 if с2 in дозволені else None
    return None


ДЕТАЛІ = ("комір", "ґудзики", "кишені", "пасок", "розріз", "рюші", "капюшон",
          "блискавка", "шнурівка", "бахрома", "кишеня_на_грудях", "манжети")
ВЗУТТЯ_НОСОК = ("гострий", "круглий", "квадратний", "мигдалевий", "відкритий")
ВЗУТТЯ_ПІДОШВА = ("тонка", "товста", "тракторна", "платформа")
ВЗУТТЯ_ХАЛЯВА = ("нема", "низька", "до_щиколотки", "середина_литки", "коліно", "вище_коліна")
СУМКА_ТИП = ("шопер", "тоут", "кросбоді", "клатч", "багет", "рюкзак", "поясна", "сумка_на_плече", "валіза")
СУМКА_РОЗМІР = ("мікро", "мала", "середня", "велика")
СУМКА_РУЧКИ = ("коротка_ручка", "довгий_ремінь", "обидва", "ланцюжок", "нема")
СУМКА_ФУРНІТУРА = ("золотиста", "срібляста", "чорна", "нема")
ПРИКРАСА_МЕТАЛ = ("золотистий", "срібястий", "чорний", "кольоровий", "нема")
ПРИКРАСА_МАСШТАБ = ("мініатюрна", "середня", "велика")


def нормалізувати(сире, набір):
    """Сира відповідь моделі → поля словників правил (і лише вони)."""
    о = {"опис": str(сире.get("опис") or "")[:300],
         "слово_моделі": _слово(сире.get("колір_слово"), V.ЛЕКСИКОН, V.назва_кольору),
         "блиск": _число(сире.get("блиск"), 0, 2, ціле=True),
         "формальність": _число(сире.get("формальність"), 1, 10, ціле=True)}
    if набір in ("одяг", "дрібне"):
        о["візерунок"] = _слово(сире.get("візерунок"), ВІЗЕРУНКИ,
                                lambda с: V.клас_мотиву(с)["клас"])
        о["матеріал"] = _слово(сире.get("матеріал"), МАТЕРІАЛИ, V.волокно_зі_слова)
    if набір == "одяг":
        о["крій"] = _слово(сире.get("крій"), КРОЇ)
        дов = _слово(сире.get("довжина"), ДОВЖИНИ)
        о["довжина"] = ДОВЖИНА_В_РІВЕНЬ.get(дов, дов)
        деталі = сире.get("деталі") if isinstance(сире.get("деталі"), list) else []
        о["деталі"] = [д for д in dict.fromkeys(str(x).strip().lower() for x in деталі) if д in ДЕТАЛІ][:5]
    if набір == "взуття":
        к = сире.get("каблук") if isinstance(сире.get("каблук"), dict) else {}
        о["каблук"] = dict(є=bool(к.get("є")) if к.get("є") is not None else None,
                           форма=_слово(к.get("форма"), ("тонкий", "товстий")),
                           висота=_слово(к.get("висота"), ("високий", "низький")))
        о["носок"] = _слово(сире.get("носок"), ВЗУТТЯ_НОСОК)
        о["підошва"] = _слово(сире.get("підошва"), ВЗУТТЯ_ПІДОШВА)
        о["халява"] = _слово(сире.get("халява"), ВЗУТТЯ_ХАЛЯВА)
        о["матеріал"] = _слово(сире.get("матеріал"), МАТЕРІАЛИ, V.волокно_зі_слова)
    if набір == "сумка":
        о["тип"] = _слово(сире.get("тип"), СУМКА_ТИП)
        о["розмір"] = _слово(сире.get("розмір"), СУМКА_РОЗМІР)
        о["ручки"] = _слово(сире.get("ручки"), СУМКА_РУЧКИ)
        о["фурнітура"] = _слово(сире.get("фурнітура"), СУМКА_ФУРНІТУРА)
        о["матеріал"] = _слово(сире.get("матеріал"), МАТЕРІАЛИ, V.волокно_зі_слова)
    if набір == "прикраса":
        о["метал"] = _слово(сире.get("метал"), ПРИКРАСА_МЕТАЛ)
        о["масштаб"] = _слово(сире.get("масштаб"), ПРИКРАСА_МАСШТАБ)
    return о
