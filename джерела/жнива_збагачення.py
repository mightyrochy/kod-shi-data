def _качати(url, тайм=20):
    # кирилиця в шляху фото (stolyarchuk) — urllib не кодує сам: 'ascii' codec can't encode
    url = urllib.parse.quote(url, safe=":/?&=%#+@;,~!$*'()[]")
    зап = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (kod-shi zbahachennya)"})
    for спроба in range(3):
        try:
            with urllib.request.urlopen(зап, timeout=тайм) as в:
                return в.read()
        except urllib.error.HTTPError:
            raise
        except OSError:
            if спроба == 2:
                raise
            _чекати_мережу()
            time.sleep(2)


def стиснути(сирі, сторона=512):
    from PIL import Image
    im = Image.open(io.BytesIO(сирі))
    if im.mode in ("RGBA", "LA", "P"):
        im = im.convert("RGBA")
        тло = Image.new("RGB", im.size, (255, 255, 255))
        тло.paste(im, mask=im.split()[-1])
        im = тло
    else:
        im = im.convert("RGB")
    im.thumbnail((сторона, сторона))
    буф = io.BytesIO()
    im.save(буф, "JPEG", quality=85)
    return base64.b64encode(буф.getvalue()).decode("ascii")


def _промпт(тип):
    return (ПРОМПТ.replace("{тип}", тип)
            .replace("{кольори}", ", ".join(КОЛЬОРИ)).replace("{матеріали}", ", ".join(МАТЕРІАЛИ))
            .replace("{крої}", ", ".join(КРОЇ)).replace("{візерунки}", ", ".join(ВІЗЕРУНКИ))
            .replace("{шаблон}", ШАБЛОН))


def _число(v, lo, hi, ціле=False):
    try:
        x = float(v)
    except (TypeError, ValueError):
        return None
    x = min(hi, max(lo, x))
    return int(round(x)) if ціле else round(x, 2)


def _колір(к):
    """{слово, hex, частка, слово_моделі} або None. Слово — через verify.назва_кольору,
    тобто тим самим розбирачем, що й слово крамниці."""
    if not isinstance(к, dict):
        return None
    сире = str(к.get("слово") or "").strip().lower()
    слово = сире if сире in V.ЛЕКСИКОН else V.назва_кольору(сире)
    if not слово:
        return None
    hex_ = str(к.get("hex") or "").strip()
    hex_ = hex_ if re.fullmatch(r"#[0-9a-fA-F]{6}", hex_) else None
    вих = dict(слово=слово, hex=hex_, частка=_число(к.get("частка"), 0, 1))
    if сире != слово:
        вих["слово_моделі"] = сире
    return вих


def нормалізувати(о):
    """Сира відповідь моделі → поля словників правил. Що не лягає в словник — null."""
    з = lambda k: str(о.get(k) or "").strip().lower() or None
    м = з("матеріал")
    м = м if м in МАТЕРІАЛИ else (V.волокно_зі_слова(м) if м else None)
    м = м if м in МАТЕРІАЛИ else None
    кр = з("крій")
    дов = з("довжина")
    дов = ДОВЖИНА_В_РІВЕНЬ.get(дов, дов) if дов in ДОВЖИНИ else None
    вз = з("візерунок")
    вз = вз if вз in ВІЗЕРУНКИ else (V.клас_мотиву(вз)["клас"] if вз else None)
    return {"опис": str(о.get("опис") or "")[:300],
            "колір_основний": _колір(о.get("колір_основний")),
            "колір_другий": _колір(о.get("колір_другий")),
            "матеріал": м,
            "крій": кр if кр in КРОЇ else None,
            "довжина": дов,
            "блиск": _число(о.get("блиск"), 0, 3, ціле=True),
            "візерунок": вз,
            "формальність": _число(о.get("формальність"), 1, 10, ціле=True),
            "впевненість": _число(о.get("впевненість"), 0, 1) or 0.0}


def спитати(модель, b64, тип, тайм=120, повтори=2):
    тіло = {"model": модель, "temperature": 0, "max_tokens": 450,
            "messages": [{"role": "user", "content": [
                {"type": "text", "text": _промпт(тип)},
                {"type": "image_url", "image_url": {"url": "data:image/jpeg;base64," + b64}}]}]}
    дані = json.dumps(тіло).encode("utf-8")
    for спроба in range(повтори + 1):
        try:
            зап = urllib.request.Request(СЕРВЕР, data=дані, headers={"Content-Type": "application/json"})
            with urllib.request.urlopen(зап, timeout=тайм) as в:
                відп = json.load(в)
            текст = відп["choices"][0]["message"]["content"].strip()
            м = re.search(r"\{.*\}", текст, re.S)
            if not м:
                raise ValueError("не JSON: %r" % текст[:80])
            return нормалізувати(json.loads(м.group(0))), відп.get("usage", {})
        except Exception:
            if спроба == повтори:
                raise
            time.sleep(3)


def тип_для_промпту(o):
    сл = None
    try:
        сл = F.слоти(o).get("слот")
    except Exception:
        pass
    тип = (o.get("параметри") or {}).get("тип") or сл or (o.get("категорія") or "").split("/")[-1].strip()
    return тип or "річ одягу", сл


def описати(o, модель):
    """Перше фото; друге — якщо перше не скачалось або модель мало що бачить."""
    тип, сл = тип_для_промпту(o)
    фото = list(o.get("фото") or []) or list(o.get("фото_сирі") or [])
    найкраще, помилки = None, []
    for i, url in enumerate(фото[:2]):
        try:
            b64 = стиснути(_качати(url))
            опис, _ = спитати(модель, b64, тип)
        except Exception as e:
            помилки.append("фото%d: %s" % (i + 1, str(e)[:120]))
            continue
        опис["фото"] = url
        опис["фото_номер"] = i + 1
        if найкраще is None or опис.get("впевненість", 0) > найкраще.get("впевненість", 0):
            найкраще = опис
        if найкраще.get("впевненість", 0) >= 0.5:
            break
    if найкраще is None:
        return dict(помилка="; ".join(помилки) or "нема фото")
    найкраще.update(тип_запиту=тип, модель=модель, знято=time.strftime("%Y-%m-%d"))
    return найкраще


def читати_збагачення(шлях=ВИХІД):
    for ш in (шлях, шлях + ".gz"):
        if os.path.exists(ш):
            відкр = gzip.open if ш.endswith(".gz") else open
            with відкр(ш, "rt", encoding="utf-8") as f:
                return json.load(f)
    return {}


def записати(дані, шлях=ВИХІД):
    тимч = шлях + ".tmp"
    with open(тимч, "w", encoding="utf-8") as f:
        json.dump(дані, f, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
    os.replace(тимч, шлях)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ліміт", type=int, default=None)
    ap.add_argument("--потоки", type=int, default=4)
    ap.add_argument("--модель", default="qwen3-vl-8b-instruct")
    ap.add_argument("--каталог", default=КАТАЛОГ)
    ap.add_argument("--вихід", default=ВИХІД)
    ap.add_argument("--випадково", action="store_true", help="перемішати чергу (для проби)")
    а = ap.parse_args()

    with gzip.open(а.каталог, "rb") if а.каталог.endswith(".gz") else open(а.каталог, "rb") as f:
        offers, _ = F.читати_yml(f)
    дані = читати_збагачення(а.вихід)
    черга =[o for o in offers if o["id"] not in дані or "помилка" in дані[o["id"]]]
    if а.випадково:
        random.Random(7).shuffle(черга)
    if а.ліміт:
        черга = черга[:а.ліміт]
    print("речей %d · готово %d · у черзі %d · потоків %d" % (
        len(offers), len(offers) - len(черга), len(черга), а.потоки), flush=True)

    замок = threading.Lock()
    t0, зроблено, збої, від_запису = time.time(), 0, 0, 0
    with ThreadPoolExecutor(а.потоки) as пул:
        майбутні = {пул.submit(описати, o, а.модель): o for o in черга}
        for м in as_completed(майбутні):
            o = майбутні[м]
            try:
                р = м.result()
            except Exception as e:
                р = dict(помилка=str(e)[:200])
            with замок:
                дані[o["id"]] = р
                зроблено += 1
                збої += "помилка" in р
                від_запису += 1
                if від_запису >= 20:
                    записати(дані, а.вихід); від_запису = 0
                if зроблено % 50 == 0 or зроблено == len(черга):
                    с = time.time() - t0
                    шв = зроблено / с if с else 0
