def метал_речі(lab, слот=None):
    """«золото» / «рожеве_золото» / «срібло» / None — чи читається КОЛІР як метал (K-PAL-11).

    Це НЕ вимір металу: фід не каже «латунь», і сказати він цього не може. Це те
    саме, чим система вже судить колір, — точка в LCh проти двох вікон.
    ⚠ БЕЗ СЛОТА ЦЕ ТВЕРДЖЕННЯ ПРО КОЛІР, А НЕ ПРО РІЧ. Вікно золота накриває
    камель і бежевий (виміряно на каталог_повний: 166 речей пулу читаються
    «металом», з них більшість — бежеві футболки й сорочки), а вікно срібла —
    будь-який світлий ахромат. Метал стає твердженням про РІЧ лише там, де річ і
    є фурнітурою (`СЛОТИ_МЕТАЛУ`), — тому викликач, який питає про річ, передає
    `слот`, і тоді поза цими слотами відповідь None.
    Срібло перевіряється першим: його вікно вужче й лежить усередині ахромату.
    Рожеве золото — останнім: воно відповідає лише там, де мовчать обидва старші
    вікна, тож жодна доти дана відповідь від нього не міняється (рядок 226).
    """
    if слот is not None and слот not in СЛОТИ_МЕТАЛУ:
        return None
    # п.14 (20.09.2026): усі три живі викликачі (`суд_від_моделі._lab_з`, `фід_добір`
    # після власного `lch`) дають готовий Lab; не-Lab тут — помилка викликача, і вона
    # летить у `bridge.виклик` (`помилка` + `код`), а не читається як «не метал».
    L, C, h = cs.lch(tuple(lab))
    if СРІБЛО["L"][0] <= L <= СРІБЛО["L"][1] and C <= СРІБЛО["C"][1]:
        return "срібло"
    if (ЗОЛОТО["L"][0] <= L <= ЗОЛОТО["L"][1] and ЗОЛОТО["C"][0] <= C <= ЗОЛОТО["C"][1]
            and ЗОЛОТО["дуга"][0] <= h <= ЗОЛОТО["дуга"][1]):
        return "золото"
    if (РОЖЕВЕ_ЗОЛОТО["L"][0] <= L <= РОЖЕВЕ_ЗОЛОТО["L"][1]
            and РОЖЕВЕ_ЗОЛОТО["C"][0] <= C <= РОЖЕВЕ_ЗОЛОТО["C"][1]
            and РОЖЕВЕ_ЗОЛОТО["дуга"][0] <= h <= РОЖЕВЕ_ЗОЛОТО["дуга"][1]):
        return "рожеве_золото"
    return None

