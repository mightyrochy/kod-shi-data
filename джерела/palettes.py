# ── ЯСНІСТЬ РИС: ВОЛОССЯ БЕЗ ТОНУ ГОЛОСУЄ ЛИШЕ СВІТЛОТОЮ ──
# Вісь «м'яка–ясна» — середнє rel_C рис. Чорне волосся (C*≈3) у ньому тягло б вісь
# вниз кожній темноволосій: ж3 (порцеляна L*88, волосся L*11, контраст 75) вийшла б «soft
# −0.61», «найдальші — ясні». rel_C = C/c_max(L, h) ділить на стелю ПРИ ТОНІ, а тону
# в рисі з C* нижче межі нейтралі нема (K-COL-06: «тону з неї не взяти»). Виміряно на
# тестових жінках: те саме на око чорне волосся дає rel_C 0.06 (ж3, L*11), 0.22 (ж8,
# L*6) і 0.27 (ж4, L*5) — розкид ушестеро від шуму тону, не від ясності.
# Корпус каже, як голосує ахроматичне волосся: «votes only by lightness»
# (K-ECHO-01, «Where it breaks»; K-TIME-01). Волосся з C* < `neutral_C` у середнє
# ясності не входить; у світлоту (вісь value, «її чорний») — входить. Шкіра
# й очі голосують завжди. Якщо голосів не лишилось, вісь — середина (0.0).
def ясність_рис(F):
    """Середнє rel_C рис, що несуть тон: шкіра, очі й волосся з C* ≥ `neutral_C` (K-COL-06).

    Чому так: rel_C ділить на стелю гамуту при тоні риси; у волосся без тону (C* нижче
    межі нейтралі) це шум, а корпус велить такому волоссю голосувати лише світлотою
    (K-ECHO-01 / K-TIME-01). Повертає None, коли голосів нема. Ту саму величину бере
    `bases.ранг` за ціль хроми основи, коли жінка не відповіла про свої барви."""
    межа = float(_РЕЄСТР.C["neutral_C"])
    rel = [f.get("rel_C", 0.0) or 0.0 for nm, f in PP.дані(F).items()
           if not (PP.рід_риси(nm) == "волосся" and float(f.get("C") or 0.0) < межа)]
    return (sum(rel) / len(rel)) if rel else None
ДОМІНАНТА_МІН = 0.25       # |позиція| нижче — вісь не домінує (людина «серединна» по ній)

def _клип(x, lo=-1.0, hi=1.0):
    """Обрізає x до [lo, hi]."""
    return max(lo, min(hi, x))

