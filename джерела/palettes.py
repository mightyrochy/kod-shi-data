def найдальші(ос):
    """Область кольорів, обернена по всіх виражених осях людини (K-PAL-14): вікна L/C, дуги сімей і
    слова.

    Чому так: знак індукції не встановлений, тож «гірші» як вимір неможливі;
    практики дають протилежний тон (Sci\ART) і «washed out» (Lamport). Це
    «найдальші», не «заборонені»: сила hint; як їх усе ж нести — K-PAL-08/09. Вісь
    обертається, лише коли |позиція| ≥ половини `_ДОМІНАНТА_МІН`."""
