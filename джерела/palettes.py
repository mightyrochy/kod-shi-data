    for c in П["кольори"]:
        if c["роль"] == "колір": сім.setdefault(c["сім_я"], []).append(c["назва"])
    ч.append("Сім'ї у вашій версії: " + "; ".join("%s — %s" % (s, ", ".join(dict.fromkeys(n))) for s, n in сім.items()) + ".")
    н = [c for c in П["кольори"] if c["роль"] != "колір"]
    if н: ч.append("Ваші нейтралі: " + ", ".join(dict.fromkeys("%s (%s, L*%.0f)" % (c["назва"], c["температура"], c["L"]) for c in н)) + ".")
    акт = [x["прийом"] for x in П["прийоми"] if x["активний"]]
    ч.append("Прийоми, доступні зараз: " + ", ".join(акт) + ".")
    if П.get("найдальші"): ч.append("Найдальші від ваших осей (не заборона — нести далі від обличчя або на контрасті): %s." % П["найдальші"]["словами"])
    for p in (П.get("поєднання") or [])[:4]:
        ч.append("Поєднання (%s): %s." % (p["прийом"], " + ".join("%s %s" % (x["назва"], x["hex"]) for x in p["кольори"])))
    оз = [c["назва"] for c in П["кольори"] if c.get("сезон_гардеробу") == "осінь-зима"][:6]
    вл = [c["назва"] for c in П["кольори"] if c.get("сезон_гардеробу") == "весна-літо"][:6]
    if оз or вл: ч.append("За сезоном гардероба: осінь-зима — %s; весна-літо — %s." % (", ".join(dict.fromkeys(оз)) or "—", ", ".join(dict.fromkeys(вл)) or "—"))
    ч.append(П["статус"])
    return " ".join(ч)
