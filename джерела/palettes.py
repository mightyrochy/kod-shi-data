# ── K-PCA-01 ЗНАК-ПРОКСІ: напрям індукції на шкіру проти «здоровішого» ────────
# Ціль практиків (K-PCA-01): шкіра рівніша, тіні слабші, «живо». Виміряні мости:
# Stephen 2009 — червоніша/жовтіша шкіра читається здоровішою (в межах);
# R-CHEV-07 — річ штовхає тон шкіри ВІД свого тону. Отже річ, чий відштовх веде
# шкіру до +a*/+b* (тепліше-червоніше), рухає у «здоровіший» бік; протилежна — від
# нього. ПЕРЕНОС на масштаб обличчя НЕ ВИМІРЯНИЙ (T4), перевага нелінійна й
# культурно залежна — тому це ІНФОРМАЦІЯ і ОСТАННІЙ ключ сортування, не фільтр.
def знак_проксі(h_речі, h_шкіри):
    """Бік індукції речі на шкіру — «до здоровішого» чи «від здоровішого» — за кутами тону речі й
    шкіри; None без одного з кутів.

    Чому так: K-PCA-01 через два виміряні мости — Stephen 2009 (червоніша/жовтіша
    шкіра, ціль ≈50°, читається здоровішою) і R-CHEV-07 (річ штовхає тон шкіри ВІД
    свого тону). Величина зсуву 8° — не вимір: важить лише напрям. Перенос на масштаб
    обличчя не виміряний (T4), тому це інформація й останній ключ сортування в
    `палітра_практична`, не фільтр; сила hint."""
    if h_речі is None or h_шкіри is None: return None
    dh = (float(h_речі) - float(h_шкіри) + 180) % 360 - 180
    # відштовх від тону речі: скін зсувається на −sign(dh) по куту; «здоровіший» бік
    # (Stephen) — до ~40–60° (жовто-червоний). Позитив, якщо зсув веде туди.
    ціль = 50.0
    після = (float(h_шкіри) - 8.0 * (1 if dh > 0 else -1)) % 360
    before, after = abs((float(h_шкіри) - ціль + 180) % 360 - 180), abs((після - ціль + 180) % 360 - 180)
    return dict(бік=("до здоровішого" if after < before else "від здоровішого"),
                правило="K-PCA-01", тир="T4 перенос", сила="hint")

# ── ОСІ: ПОЗИЦІЯ ЛЮДИНИ, НЕПЕРЕРВНО ─────────────────────────────────────────
# Масштаби T3: середина 50 L* / 0.45 rel_C і пів-ширини 25 / 0.25 — конвенція, щоб
# «світла» ≈ середня L рис > 75, «глибока» < 25; калібрування проти драпінгу нема.
_СЕРЕД_L, _ПІВ_L = 50.0, 25.0
_СЕРЕД_C, _ПІВ_C = 0.45, 0.25

# ── ЯСНІСТЬ РИС: ВОЛОССЯ БЕЗ ТОНУ ГОЛОСУЄ ЛИШЕ СВІТЛОТОЮ (рядок 1401, 02.10.2026) ──
# БУЛО. Вісь «м'яка–ясна» — середнє rel_C УСІХ рис, і чорне волосся (C*≈3) тягло її
# вниз кожній темноволосій: ж3 (порцеляна L*88, волосся L*11, контраст 75) — «soft
# −0.61», «найдальші — ясні». rel_C = C/c_max(L, h) ділить на стелю ПРИ ТОНІ, а тону
# в рисі з C* нижче межі нейтралі нема (K-COL-06: «тону з неї не взяти»). Виміряно на
# тестових жінках: те саме на око чорне волосся дає rel_C 0.06 (ж3, L*11), 0.22 (ж8,
# L*6) і 0.27 (ж4, L*5) — розкид ушестеро від шуму тону, не від ясності.
# ТЕПЕР. Корпус уже каже, як голосує ахроматичне волосся: «votes only by lightness»
# (K-ECHO-01, «Where it breaks»; K-TIME-01). Волосся з C* < `neutral_C` у середнє
# ясності не входить; у світлоту (вісь value, «її чорний») — входить, як доти. Шкіра
# й очі голосують завжди. Якщо голосів не лишилось, вісь — середина (0.0).
def ясність_рис(F):
    """Середнє rel_C рис, що несуть тон: шкіра, очі й волосся з C* ≥ `neutral_C` (K-COL-06).

    Чому так: rel_C ділить на стелю гамуту при тоні риси; у волосся без тону (C* нижче
    межі нейтралі) це шум, а корпус велить такому волоссю голосувати лише світлотою
    (K-ECHO-01 / K-TIME-01). Повертає None, коли голосів нема. Ту саму величину бере
    `bases.ранг` за ціль хроми основи, коли жінка не відповіла про свої барви."""
    межа = float(_РЕЄСТР.C["neutral_C"])
    rel = [f.get("rel_C", 0.0) or 0.0 for nm, f in PP._дані(F).items()
           if not (PP.рід_риси(nm) == "волосся" and float(f.get("C") or 0.0) < межа)]
    return (sum(rel) / len(rel)) if rel else None
_ДОМІНАНТА_МІН = 0.25       # |позиція| нижче — вісь не домінує (людина «серединна» по ній)

def _клип(x, lo=-1.0, hi=1.0):
    """Обрізає x до [lo, hi]."""
    return max(lo, min(hi, x))

# КОД БОКУ ОСІ → СЛОВО. Одна таблиця на всю систему. Після злиття Ч-3 (#389) і П-5 у
# ПРОДУКТІ її не читає вже НІХТО: екран бере коди (`осі(...)["коди"]`, `показ.html` →
# `осі_коди`), а проза брифа функціональної моделі (`словами(П)`) знята — у пакет їдуть
# коди й числа (`для_пакета`). Єдиний читач, що лишився, — гейт `прилади/розділи_гейтів`
# (§137 звіряє слово утриманої осі). Знімати таблицю разом із `осі(...)["словами"]` —
# окремий наряд: це правка приладу, не продукту.
БІК_СЛОВОМ = {"light": "світла", "mid_lightness": "середня за світлотою", "deep": "глибока",
              "soft": "м'яка", "mid_chroma": "середня за ясністю", "clear": "ясна",
              "cool": "холодна", "neutral": "нейтральна", "warm": "тепла",
              "withheld": "не стверджується"}

def осі(F, source="uncontrolled", самозвіт=None):
    """Позиція на трьох осях ∈ [−1, +1]: value (−світла … +глибока), chroma (−м'яка … +ясна),
    hue (−холодна … +тепла). Домінанта — вісь із найбільшим |p| понад поріг."""
    д = PP._дані(F)
    Ls = [f["L"] for f in д.values()]
    ясн = ясність_рис(F)
    p_value = _клип((_СЕРЕД_L - sum(Ls)/len(Ls)) / _ПІВ_L) if Ls else 0.0
    p_chroma = _клип((ясн - _СЕРЕД_C) / _ПІВ_C) if ясн is not None else 0.0
    R = cs.reliability(source)
    sk = F.get("шкіра") or {}
    тепло = sk.get("тепло_сила")
    надійно = R["undertone"] >= cs.MIN_TO_EMIT
    джерело_hue = "фото"
    if самозвіт and (самозвіт.get("метал") or самозвіт.get("білий")):
        # елісітація не залежить від камери: золото/теплий білий → +, срібло/холодний → −
        зн = 0
        відповідей = 0
        if самозвіт.get("метал") == "золото": зн += 1; відповідей += 1
        if самозвіт.get("метал") == "срібло": зн -= 1; відповідей += 1
        if самозвіт.get("білий") == "теплий": зн += 1; відповідей += 1
        if самозвіт.get("білий") == "холодний": зн -= 1; відповідей += 1
        # ── СЕРЕДНЄ ПО КАНАЛАХ, А НЕ СУМА (Н-V04-011) ────────────────────────
        # Тут стояло `_клип(0.6 * зн)` на СУМІ каналів, і рядок нижче про стелю
        # 0.6 був неправдою: два узгоджені голоси давали 0.6·(±2) → клип ±1.00,
        # тобто РІВНО максимум осі. Виміряно на стенді: домінанта переїжджала з
        # value −0.92 на hue −1.00, і дві відповіді на картках важили більше за
        # виміряну світлоту людини. Обіцянка двома рядками вище — «самозвіт дає
        # БІК, не величину»; середнє її й виконує: один узгоджений голос і два
        # дають те саме 0.6, другий голос ПІДТВЕРДЖУЄ бік, а не подвоює його.
        # Суперечливі відповіді (золото + холодний білий) дають 0.0 — бік не
        # названий, і це чесніше за половину боку з залишку суми.
        # 0.6 — стеля самозвіту (T3): він сильніший за утримане фото, але не
        # сильніший за вимір, який стоїть на власних осях value/chroma.
        p_hue = _клип(0.6 * зн / max(1, відповідей))
        джерело_hue = "самозвіт"
    elif тепло is not None and надійно and sk.get("вісь_знак_придатний") is not False:
        # ── ГІЛКА ФОТО ПІД ТИМ САМИМ ГЕЙТОМ, ЩО Й ВІКНО (Н-V04-013, крок 4) ──
        # `надійно` питає про ЯКІСТЬ ЗАХОПЛЕННЯ, а `вісь_знак_придатний` — про те,
        # чи вісь узагалі двостороння на оголошеній популяції. Це різні питання, і
        # доти відповідь на друге тут не питалась узагалі: на `protocolized` вихід
        # давав «тепла (1.00; фото)» — максимум осі — зі знака, який `colorspace`
        # відмовився стверджувати. Гілка `else` (утримання) нижче вже написана
        # правильно: вона й приймає цей випадок.
        p_hue = _клип(float(тепло) / 1.5)    # тепло_сила ∈ [−1.5, 1.5] (colorspace)
    else:
        p_hue = 0.0
        # без ID правила: цей рядок їде в промпт моделі (palettes.словами → бриф руки),
        # а ID корпусу в тексті для моделі — витік (спіймано гейтом §41, 28.08.2026);
        # правило лишається в сліді: colorspace/K-PC-05 його записує
        джерело_hue = "утримано: підтон із фото не стверджується → нейтральна"
    поз = dict(value=round(p_value, 2), chroma=round(p_chroma, 2), hue=round(p_hue, 2))
    порядок = sorted(поз.items(), key=lambda kv: -abs(kv[1]))
    домінанта = порядок[0][0] if abs(порядок[0][1]) >= _ДОМІНАНТА_МІН else None
    вторинна = порядок[1][0] if домінанта and abs(порядок[1][1]) >= _ДОМІНАНТА_МІН else None
    # ── СЛОВО МУСИТЬ МАТИ СЕРЕДИНУ (08.09.2026) ─────────────────────────────
    # ЗНАЙДЕНО ПРОБОЮ, І ЦЕ БУЛО ВИДНО В ПРОМПТІ МОДЕЛІ ДОСЛІВНО:
    #   «температура — ТЕПЛА (0.00; утримано: підтон із фото не стверджується
    #    → нейтральна)»
    # Тобто в одному реченні система і стверджує бік, і каже, що не стверджує.
    # Причина — двійкове `"холодна" if p < 0 else "тепла"` без випадку нуля, а
    # `p_hue` при утриманні дорівнює РІВНО 0.0 ЗА ПОБУДОВОЮ. Отже неправда
    # виходила не зрідка, а КОЖНОМУ, хто прийшов із неконтрольованого фото, —
    # тобто всім на живому шляху. Читач бере перше слово, не дужку.
    #
    # Поріг середини — той самий `_ДОМІНАНТА_МІН`, яким модуль уже вирішує, що
    # «вісь не домінує, людина серединна по ній». Заводити друге число під те
    # саме поняття не можна: розійдуться.
    def _бік(p, низ, серед, верх):
        """КОД боку осі з середнім випадком: |p| < `_ДОМІНАНТА_МІН` → `серед`, інакше бік за знаком.

        Чому так: без середини утримана вісь (p = 0.0 за побудовою) звалась «тепла»
        кожному з неконтрольованого фото (08.09.2026); поріг той самий, що для
        домінанти, щоб не заводити друге число під одне поняття.

        Ч-3 (27.09.2026, CLAUDE.md п.12): доти функція звалась `_слово` і віддавала
        УКРАЇНСЬКЕ СЛОВО («тепла», «не стверджується»), а `показ.html` на ньому ще й
        ГІЛКУВАВСЯ (`слово === 'нейтральна'`) — тобто код і писав слово людині (кошик В),
        і читав своє ж слово як умову (кошик Б). Тепер це коди; слово на екрані — сталий
        напис показу, по одному на код. П-5 (того ж дня): проза брифа, що брала ці слова
        для моделі, знята — `коди` лишаються єдиним, чим цей вузол говорить."""
        return серед if abs(p) < _ДОМІНАНТА_МІН else (низ if p < 0 else верх)
    коди = dict(value=_бік(p_value, "light", "mid_lightness", "deep"),
                chroma=_бік(p_chroma, "soft", "mid_chroma", "clear"),
                # утримання сильніше за середину: коли осі нема ЧЕРЕЗ НАДІЙНІСТЬ,
                # чесно сказати `withheld`, а не `neutral` — це різні відповіді, і
                # друга виглядає як вимір.
                hue=("withheld" if джерело_hue.startswith("утримано")
                     else _бік(p_hue, "cool", "neutral", "warm")))
    # ── ВИСОКИЙ КОНТРАСТ НОСИТЬ ОБИДВА ПОЛЮСИ СВІТЛОТИ (рядок 1401, 02.10.2026) ──
    # БУЛО. `p_value` — середня світлота рис, і темне волосся робило «глибокою» навіть
    # порцелянову шкіру: ж3 (шкіра L*88, волосся L*11, контраст 75) діставала вікно L
    # 5–74, ж8 (L*81 / L*6, контраст 72) — 5–50, і обидві — «найдальші: світлі».
    # Палітра казала «уникай світлого біля обличчя», а суддя K-CLR-02 при її контрасті
    # світле дозволяє (стеля = власний перепад + 15): дві відповіді на одне питання.
    # ТЕПЕР. Корпус про висококонтрастну людину: «repeat the degree of contrast in the
    # clothes that frame the face» (Flusser), «create contrast in your outfits» (Lamport,
    # K-CON-01). Повторити перепад можна лише маючи обидва кінці, тож за рівня «високий»
    # (той самий `outfit.контраст_особи`, що в ранзі основ і суді) вікно L — її власна
