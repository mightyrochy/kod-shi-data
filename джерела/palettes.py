# (`колір_річ.несе_тон`: вимір з допуском, слово — вікном, не центром); тональна приглушена
# (C* 14–34 лежить і в теплому коридорі нейтралі), тож виміряна річ понад ахромат у дузі — теж тон.
ВЕЛИКІ_ТОНАЛЬНОЇ = ("верх", "низ", "сукня", "комплект", "верхній_шар")


def тон_тональної(речі, спец_слоти, за_ід=None):
    """{великих_виміряно, великих_на_тоні, на_тоні: [слоти]} або None — схема не тональна.

    «Виміряно» — у речі є колір (вимір чи вікно слова), і це не прикраса, чий колір знає лише
    слово металу."""
    if not isinstance(спец_слоти, dict) or спец_слоти.get("_схема") != "тональна":
        return None
    import колір_річ as _КР
    вел_вим, вел_тон, на_тоні = 0, 0, []
    for r in (речі or []):
        повна = (за_ід or {}).get(r.get("id")) or r
        сл = r.get("слот") or повна.get("слот")
        сп = спец_слоти.get(сл) if isinstance(спец_слоти.get(сл), dict) else {}
        lab = _lab_повної(повна)
        if not lab or _колір_невідомий(повна):
            continue
        вел = сл in ВЕЛИКІ_ТОНАЛЬНОЇ
        вел_вим += вел
        д = сп.get("дуга_тону")
        тон = bool(д) and _КР.несе_тон(dict(повна, lab=lab), д) is not None
        if д and not тон and not повна.get("колір_не_вимір") and not метал_речі(lab, сл):
            _L, C, h = cs.lch(lab)
            доп = _КР.допуск_тону(C)
            тон = C >= cs.ACHROMATIC_C and _КР._на_дузі(
                h % 360.0, ((float(д[0]) - доп) % 360.0, (float(д[1]) + доп) % 360.0))
        if тон:
            вел_тон += вел
            на_тоні.append(сл)
    return dict(великих_виміряно=вел_вим, великих_на_тоні=вел_тон, на_тоні=на_тоні)


def обіцянка_схеми(речі, спец_слоти, за_ід=None, кандидати=None, тіло=None, межа_людини=None):
    """[знахідки] K-COL-03 — чи образ виконує те, що обіцяла обрана схема.

    Схема великих поверхонь (тріада, приглушена комплементарна — `_поверхні` у спеці
    слотів, рядок 133) судиться інакше: її сім'ї мусять стояти на ВЕЛИКИХ речах, і
    приблизно порівну. Це міряє `palette.обіцянка_великих` (там само, де означення
    сім'ї, яким пул їх і добирав); `кандидати` й `тіло` потрібні лише їй — «брак
    асортименту» й площі.

    Дві гілки, дзеркальні:
      · схема просить акцент, а в образі НЕМА ЖОДНОЇ кольорової речі — обіцянка
        не виконана (це «blandness» корпусу, а не «спокійний образ»);
      · схема «нейтрали+акцент» обіцяє ОДИН акцент, а образ несе дві й більше
        РІЗНИХ кольорових сімей — обіцянка не виконана з другого боку.
    Обидві мовчать, коли колір жодної речі образу не виміряний: невимір — не провал
    (та сама політика, що в `pipeline.акцент_образу`).
    `за_ід` обов'язковий із тієї самої причини, що там: рядок пулу, який їде до
    моделі, `lab` не несе, і рахувати хрому по ньому означало б завжди звинувачувати.
    """
    if not спец_слоти or not isinstance(спец_слоти, dict):
        return []
    # ТРАУРНА НАГОДА, СХЕМУ ВЗЯВ КОД (рядок 154): акцент не проситься, отже й
    # обіцянки, яку можна не виконати, нема — образ без кольору тут доречний
    if спец_слоти.get("_траур"):
        return []
    # НАГОДА, ЩО АКЦЕНТУ НЕ ПРОСИТЬ, І СХЕМУ ОБРАЛА НЕ ВОНА (СХЕМА-КАРТКА, рядок 1405): служба в
    # церкві — нейтральний образ тут доречний, а не «невиконана схема»; колір у пулі лишається
    if спец_слоти.get("_нагода_без_акценту") and not any(
            _несе_колір((за_ід or {}).get(r.get("id")) or r) for r in (речі or [])):
        return []
    if спец_слоти.get("_поверхні") == "великі":
        import palette as _P_вел
        # `межа_людини` (СХЕМА-960): схему обрала вона — пропуск сім'ї, який лікує заміна, є гейтом
        return _P_вел.обіцянка_великих(речі, спец_слоти, за_ід, кандидати, тіло, межа_людини=межа_людини)
    акцентні = [с for с, сп in спец_слоти.items()
                if not str(с).startswith("_") and isinstance(сп, dict)
                and сп.get("роль") == "акцент" and сп.get("C") and float(сп["C"][0]) > 0]
    if not акцентні:
        return []                      # схема кольору не просить — нема чого звіряти
    схема = спец_слоти.get("_схема", "?")
    тт = тон_тональної(речі, спец_слоти, за_ід)
    if тт is not None:
        # ТОНАЛЬНА — ТОН НА ВЕЛИКИХ РЕЧАХ (рядок 1403): кольорова сумка при нейтральних верху й низу
        # обіцянки «один тон на всіх речах» не виконує; невимір великих — мовчання, не провал
        if not тт["великих_виміряно"] or тт["великих_на_тоні"]:
            return []
        сила = _РЕЄСТР.сила_за_корпусом("K-COL-03", "default")
        вел_сл = next((r.get("слот") for r in речі if r.get("слот") in ВЕЛИКІ_ТОНАЛЬНОЇ), "верх")
        return [dict(правило="K-COL-03", сила=сила,
                     сила_нп={"hard": 0.95, "strong": 0.75, "default": 0.5, "soft": 0.35, "hint": 0.2}.get(сила, 0.5),
                     впевненість=1.0, регістр=_РЕЄСТР.регістр("K-COL-03", сила),
                     сила_нп_джерело="сила корпусу K-COL-03 (FORCE: %s) — `реєстр_правил.сила_за_корпусом`" % сила,
                     бік="код", слот=вел_сл,
                     речі=[r.get("id") for r in речі if r.get("слот") in ВЕЛИКІ_ТОНАЛЬНОЇ and r.get("id")],
                     ярлик="тональна схема: тону нема на великих речах",
                     суть=("схема «тональна» обіцяє один тон на всіх речах, а жодна з %d виміряних великих "
                           "речей його не несе; тон є лише на: %s"
                           % (тт["великих_виміряно"], ", ".join(тт["на_тоні"]) or "—")),
                     чому="кольоровий аксесуар на нейтральному образі — це «нейтрали+акцент», не тональна",
                     ремонт="заміни одну велику річ (найкраще «%s») на річ тону схеми з пулу, кроком "
                            "світлоти від решти" % вел_сл,
                     що_зняло_б="тон схеми на великій речі",
                     заяви=[_ВМ.заява("scheme_tonal_tone_not_on_large_items",
                                      scheme=_ВМ.код_або_невідомо("palette_scheme", схема),
                                      large_measured=тт["великих_виміряно"],
                                      on_tone=[_ВМ.код_або_невідомо("slot", с) for с in тт["на_тоні"]])],
                     ремонт_заяви=[_ВМ.заява("swap_large_item_to_scheme_tone",
                                             slot=_ВМ.код_або_невідомо("slot", вел_сл))])]
    виміряні, кольорові, словом, невідомі = [], [], [], []
    for r in речі:
        повна = (за_ід or {}).get(r.get("id")) or r
        # п.14 (20.09.2026): хибний hex — річ БЕЗ виміру кольору (`_lab_повної`), та сама
        # гілка, що й без hex (політика «невимір — не провал» у докстрінгу)
        lab = _lab_повної(повна)
        if _несе_колір(повна) == "слово":
            словом.append(r)
        if not lab:
            continue
        # слово металу — ні доказ нейтралі прикраси (рядок 1480: срібло зі слова не «виміряна
        # нейтраль»), ні доказ кольору (рядок 1682: центр вікна «золотий» хроматичний, але золото
        # зі слова — не вимір і не акцент схеми): колір такої прикраси невідомий
        if _колір_невідомий(повна):
            невідомі.append(r)
            continue
        # металева основа не несе колір; вставка — окрема поверхня з власним Lab
        х_все = ([] if метал_речі(lab, r.get("слот")) else
                 [(*х, lab) for х in [_хроматична(lab)] if х])
        х_все += [х for х in [_хроматична_вставка(повна)] if х]
        виміряні.append(r)
        for в in х_все:
            if not any(r is к[0] and в[0] == к[1] for к in кольорові):
                кольорові.append((r, в[0], в[1], в[2]))
    if not виміряні:
        return []                      # входу нема — мовчати чесніше, ніж звинувачувати
    if not кольорові and словом:
        # вимір каже «нейтраль», крамниця — колір (рядок 1292): свідки розходяться, і «увесь
        # нейтральний» тут не доведено — мовчати, як і без виміру. Так само, коли акцентний
        # слот несе прикраса, чий колір знає лише слово металу (рядок 1480): обіцянку схеми
        # несе саме вона, а її кольору код не бачив
        return []
    сила = _РЕЄСТР.сила_за_корпусом("K-COL-03", "default")
    рег = _РЕЄСТР.регістр("K-COL-03", сила)
    нп = {"hard": 0.95, "strong": 0.75, "default": 0.5, "soft": 0.35, "hint": 0.2}.get(сила, 0.5)
    дж = "сила корпусу K-COL-03 (FORCE: %s) — `реєстр_правил.сила_за_корпусом`" % сила
    ід = [r.get("id") for r in речі if r.get("слот") in акцентні] or [r.get("id") for r in виміряні]
    слот = next((r.get("слот") for r in речі if r.get("слот") in акцентні), акцентні[0])
    if not кольорові:
        return [dict(правило="K-COL-03", сила=сила, сила_нп=нп, впевненість=1.0, регістр=рег,
                     сила_нп_джерело=дж, бік="код", слот=слот, речі=[x for x in ід if x],
                     ярлик="схема обіцяла акцент, образ увесь нейтральний",
                     суть=("схема «%s» обіцяє нейтралі + акцент, а в образі жодна з %d "
                           "виміряних речей не несе кольору: усе читається нейтраллю"
                           % (схема, len(виміряні))),
                     чому="це не «спокійний образ», а невиконана схема: корпус називає "
                          "нейтральну базу без акценту головним джерелом прісності",
                     ремонт="заміни ОДНУ річ (найкраще в слоті «%s») на кольорову з пулу — "
                            "решта лишається нейтральною" % слот,
                     що_зняло_б="одна кольорова річ в акцентному слоті",
                     заяви=[_ВМ.заява("scheme_promised_accent_all_neutral",
                                      scheme=_ВМ.код_або_невідомо("palette_scheme", схема), measured=len(виміряні))],
                     ремонт_заяви=[_ВМ.заява("swap_one_item_to_colour_in_slot",
                                             slot=_ВМ.код_або_невідомо("slot", слот))])]
    # ОДИН АКЦЕНТ — ЦЕ ОДИН ТОН, А НЕ ОДНА НАЗВА СІМ'Ї (ФОКУС-3, рядок 1522). Доти лічились
    # сім'ї розбиття кола (`колір_образу.FAMILIES`) по всіх кольорових речах, і на fokus_2/ПІСЛЯ
    # друга «сім'я» майже завжди була (а) золотом прикраси (`#c8ac6a` → «жовта»), хоч метал
    # прикраси читається металом, не кольором (K-PAL-11, `метал_речі` зі слотом — той самий
    # предикат, що в K-COL-02), або (б) тим самим зеленим по два боки межі сімей (h 136° і 140°),
    # хоч повтор тону — відлуння, один акцент (K-COMP-05, дуга `суд_ремесло.ДУГА_ВІДЛУННЯ`).
    # Ремонт «лиши кольоровою одну річ» знімав тоді акцент схеми: туфлі чи сумку. Тепер лічаться
    # групи тону без металу прикрас; яку групу лишити, каже `keep`, коли її оголошено.
    from суд_ремесло import ДУГА_ВІДЛУННЯ, слоти_акценту_схеми
    import колір_образу as _КО_т, регістр_уваги as _РУ_т
    групи = []
    for r, с, _C, lab in кольорові:
        повна = (за_ід or {}).get(r.get("id")) or r
        т = dict(lab=lab, колір_не_вимір=повна.get("колір_не_вимір"))
        g = next((g for g in групи if _КО_т.поруч_за_тоном(т, g["т"], ДУГА_ВІДЛУННЯ) != "ні"), None)
        if g is None:
            g = dict(т=т, сім=с, речі=[], слоти=[], оголошено=set())
            групи.append(g)
        g["речі"].append(r.get("id")); g["слоти"].append(r.get("слот"))
    _схема_сл = слоти_акценту_схеми(речі, спец_слоти)
    for g in групи:
        for ід, сл in zip(g["речі"], g["слоти"]):
            повна = (за_ід or {}).get(ід) or {}
            if сл in _схема_сл:
                g["оголошено"].add("scheme")
            if _РУ_т.її_вибір(повна):
                g["оголошено"].add("her_wish")
    if схема == "нейтрали+акцент" and len(групи) >= 2:
        лишити = [g for g in групи if g["оголошено"]]
        кд = lambda гг: sorted({_ВМ.код_або_невідомо("slot", с) for g in гг for с in g["слоти"] if с})
        # ЯКУ ГРУПУ ЛИШИТИ — лише коли оголошено рівно одну (акцент схеми чи її вибір, п.9);
        # дві оголошені чи жодної — вибір за стилісткою (CLAUDE.md п.17), як доти.
        ціль = (dict(keep=кд(лишити), quiet=кд([g for g in групи if g is not лишити[0]]),
                     keep_by=sorted(лишити[0]["оголошено"])) if len(лишити) == 1 else {})
        return [dict(правило="K-COL-03", сила=сила, сила_нп=нп, впевненість=1.0, регістр=рег,
                     сила_нп_джерело=дж, бік="код", слот=слот,
                     речі=list(dict.fromkeys(i for g in групи for i in g["речі"])),
                     ярлик="схема обіцяла ОДИН акцент, кольорових тонів більше",
                     суть=("схема «%s» обіцяє нейтралі + ОДИН акцент, а образ несе %d "
                           "кольорові тони: %s" % (схема, len(групи), ", ".join(g["сім"] for g in групи))),
                     чому="обіцянка схеми симетрична: нуль акцентів і два акценти однаково "
                          "лишають жінку з образом, якого вона не обирала",
                     ремонт="лиши кольоровим один тон (оголошений, коли він є), решту заміни на "
                            "нейтралі тієї самої смуги світлоти",
                     що_зняло_б="один кольоровий тон в образі",
                     заяви=[_ВМ.заява("scheme_one_accent_look_has_more",
                                      # сім'я тут — розбиття кола (`колір_образу.сім_я`), її перелік —
                                      # `colour_family`; з `palette_family` червона йшла «unknown»
                                      families=[_ВМ.код_або_невідомо("colour_family", g["сім"]) for g in групи],
                                      **ціль)],
                     ремонт_заяви=[_ВМ.заява("keep_one_coloured_rest_neutral",
                                             **{к: ціль[к] for к in ("keep", "quiet") if к in ціль})])]
