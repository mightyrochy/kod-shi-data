# інше означало б брехати про вимір.
# КРОК ITA — ТОЙ САМИЙ, ЩО В `лабораторія.правки_профілю.засмага`: один тон ≈ 4.5
# L* вниз при незмінному тоні. Число не нове й не наше: воно вже стоїть у лабораторії
# як модель засмаги, і тут воно ЧИТАЄТЬСЯ, а не заводиться вдруге.
_ЗАСМАГА_L_КРОК = 4.5


def засмага_не_рухає_вікна(F, source, самозвіт, очі_h):
    """K-COND-02. Чи перемикає дуги сімей зсув ПОВЕРХНІ шкіри. Вимір, не заява."""
    sk = F.get("шкіра") or {}
    if sk.get("L") is None:
        return dict(тримається=True, зсув_підтону=0.0, сімей_змінилось=0,
                    чому="шкіри в профілі нема — перевіряти нема на чому")
    засмагла = dict(F)
    засмагла["шкіра"] = dict(sk, L=max(0.0, float(sk["L"]) - _ЗАСМАГА_L_КРОК))
    ос_до = осі(F, source, самозвіт)
    ос_після = осі(засмагла, source, самозвіт)
    дуги_до = дуги_сімей(ос_до, очі_h)
    дуги_після = дуги_сімей(ос_після, очі_h)
    змінились = sorted(k for k in set(дуги_до) | set(дуги_після)
                       if дуги_до.get(k) != дуги_після.get(k))
    зсув = abs(ос_після["позиція"]["hue"] - ос_до["позиція"]["hue"])
    # ЧОМУ ІНВАРІАНТ ТРИМАЄТЬСЯ — ТЕЖ ЧАСТИНА ВІДПОВІДІ. «Тримається, бо ключ від
    # очей» і «тримається, бо осі взагалі нема» — різні новини, і друга означає, що
    # перевірка сьогодні ще нічого не доводить. Мовчати про це означало б видати
    # утримання за доказ — рівно та підміна, яку ловить увесь цей шар.
    джерело = ос_до.get("джерело_hue") or "?"
    утримано = str(джерело).startswith("утримано")
    return dict(
        тримається=not змінились,
        зсув_підтону=round(зсув, 3),
        сімей_змінилось=len(змінились),
        сім_ї=змінились or None,
        джерело_осі=джерело,
        доводить=not утримано,
        чому=(("зсув поверхні шкіри на %.1f L* не перемкнув жодної дуги сім'ї: ключ у них "
               "— очі й вісь підтону, а підтон засмага не міняє" % _ЗАСМАГА_L_КРОК
               + ("; АЛЕ сьогодні це тримається ЗА ПОБУДОВОЮ, а не як доказ: вісь підтону "
                  "утримана (%s), тож рухати їй нема чого. Перевірка стане змістовною, "
                  "щойно вісь дістане вхід — елісітацію золото/срібло або білий" % джерело
                  if утримано else "; вісь підтону має вхід (%s), тож збіг тут — вимір, "
                                   "а не наслідок мовчання" % джерело))
              if not змінились else
              "зсув поверхні шкіри на %.1f L* перемкнув дуги %s — це заборонено: засмага "
              "міняє поверхню, не підтон, і діагноз не має права їхати за нею"
              % (_ЗАСМАГА_L_КРОК, ", ".join(змінились))),
        ламається="перевіряється ОДИН крок засмаги, не вся її смуга, і лише дуги сімей: "
                  "світлотні й хромні межі вікна рухатись МУСЯТЬ — поверхня справді стала "
                  "темнішою. І це інваріант КОДУ, а не вердикт про образ: він каже, що "
                  "система не перемикає діагноз, а не що робити жінці")


# ── ЗБІРКА ───────────────────────────────────────────────────────────────────
def палітра_практична(F, source="uncontrolled", самозвіт=None, контраст_рівень=None, intent="conventional"):
    """Повна практикова палітра людини: `_палітра_практична` + поєднання, тон кожного кольору
    (R-COL-14/R-MUN-08), знак-проксі й стабільне сортування за ним (K-PCA-01), перевірений інваріант
    K-COND-02, сезон гардеробу (K-COND-05), сліди K-PAL-01/14/15 і R-COL-17.

    Чому так: K-PCA-01 — останній ключ і стабільне сортування, бо перенос на обличчя
    T4 (жоден колір не зникає, нейтралі не рухаються); K-COND-02 міряється на цій
    людині (крок ITA по L*, дуги сімей порівнюються), а не заявляється."""
    П = _палітра_практична(F, source, самозвіт, контраст_рівень, intent)
    П["поєднання"] = поєднання(П, контраст_рівень)
    h_шк = (F.get("шкіра") or {}).get("h")
    for c in П["кольори"]:
        c["тон"] = cs.тон(_КР.точка_кольору(c))        # R-COL-14 / R-MUN-08 (колір палітри — точка)
        c["знак_проксі"] = знак_проксі(c["h"], h_шк) if c["роль"] == "колір" else None
    # ── K-PCA-01 СТАВ ТИМ, ЧИМ ЙОГО ЗВЕ ВЛАСНИЙ СЛІД ────────────
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ. Слід під цим ID дослівно казав «ОСТАННІЙ КЛЮЧ
    # СОРТУВАННЯ, не фільтр» — і жодного сортування не було: `знак_проксі`
    # рахувався на кожному кольорі палітри, лягав у поле й нікуди далі не йшов.
    # Порядок кольорів при цьому НЕ декоративний: `словами` перелічує сім'ї саме
    # в ньому, і цей текст читає жінка (і модель у брифі руки). Тобто правило
    # мало впорядкувати те, що вона побачить першим, і не впорядковувало нічого.
    # ЧОМУ САМЕ ОСТАННІЙ КЛЮЧ, І ЧОМУ СОРТУВАННЯ СТАБІЛЬНЕ: перенос на масштаб
    # обличчя НЕ ВИМІРЯНИЙ (T4), перевага нелінійна й культурно залежна — тому це
    # ІНФОРМАЦІЯ, а не фільтр: жоден колір не зникає й не позначається гіршим.
    # Стабільне сортування зберігає ВЕСЬ попередній порядок усередині рівних —
    # тобто K-PCA-01 не має права перебити жоден із ключів, що стояли до нього.
    # НЕЙТРАЛІ НЕ РУХАЮТЬСЯ ЗОВСІМ: знака в них нема (він рахується лише для ролі
    # «колір»), і пересувати їх «за відсутністю знака» означало б зробити з
    # мовчання твердження. Переставляються рівно позиції кольорів між собою.
    _місця = [i for i, c in enumerate(П["кольори"]) if c.get("знак_проксі")]
    if _місця:
        _до = [П["кольори"][i]["назва"] for i in _місця]
        _відсортовані = sorted((П["кольори"][i] for i in _місця),
                               key=lambda c: 0 if c["знак_проксі"]["бік"] == "до здоровішого" else 1)
        for i, c in zip(_місця, _відсортовані):
            П["кольори"][i] = c
        _після = [П["кольори"][i]["назва"] for i in _місця]
        _зрушено = sum(1 for a, b in zip(_до, _після) if a != b)
    else:
        _зрушено = 0
    # слід K-PCA-01 — ОДИН на палітру, з агрегатом: те саме правило на 12 кольорах —
    # одна знахідка, не 12 (семантика trace.зібрати)
    _пк = [c["знак_проксі"]["бік"] for c in П["кольори"] if c.get("знак_проксі")]
    if _пк:
        _слід("K-PCA-01", "pca01_sign_proxy_induction_direction",
              значення="до здоровішого %d / від %d; позицій зрушено %d"
                       % (_пк.count("до здоровішого"), _пк.count("від здоровішого"), _зрушено),
              сила="hint")
    П["знак_проксі_порядок"] = dict(
        до_здоровішого=_пк.count("до здоровішого"), від_здоровішого=_пк.count("від здоровішого"),
        позицій_зрушено=_зрушено,
        як="останній ключ сортування кольорів палітри, стабільний; НЕ фільтр — жоден "
           "колір не зникає й не зветься гіршим. Перенос на масштаб обличчя не "
           "виміряний (T4), тому це інформація про порядок, не вердикт про колір")
    _слід("K-PAL-01", "person_palette_generating_rule", значення=П["осі"]["домінанта"], сила="default")
    _слід("R-COL-17", "feature_order_eyes_first", значення=1, сила="default")
    _слід("K-PAL-14", "farthest_colours", значення=П["найдальші"]["словами"])
    _слід("K-PAL-15", "combinations_inside_palette", значення=len(П["поєднання"]))
    # ── K-COND-02 СТАВ ПЕРЕВІРЕНИМ ІНВАРІАНТОМ, А НЕ ЗАЯВОЮ ПРО СЕБЕ ────────
    # ЩО БУЛО: рядок сліду «засмага не рухає вікна · ключ від очей». Він СТВЕРДЖУВАВ
    # властивість коду й нічого не перевіряв. Заява, яку ніхто не міряє, живе рівно
    # доти, доки її не зламає сусідня правка, — і зламається вона мовчки: слід
    # писатиме те саме речення над іншою поведінкою.
    # ЩО ПЕРЕВІРЯЄТЬСЯ: властивість МІРЯЄТЬСЯ на цій людині. Засмага — це зміна ПОВЕРХНІ
    # шкіри, а не підтону (практики: «a summer tan does not make you warm, because
    # surface colour changes while undertone does not»; вимір — Perrett 2023 Exp. 1).
    # Отже вона має право рухати світлотні числа й НЕ МАЄ права перемикати ДУГИ
    # СІМЕЙ, бо ключ у них — очі (`_дуги_сімей(ос, очі_h)`) і вісь підтону.
    # Перевірка: темнимо шкіру на крок ITA (лише L*, тон не чіпаємо — саме так діє
    # засмага), перераховуємо осі й дуги й порівнюємо. Збіг — інваріант тримається,
    # і слід несе ВИМІР, а не обіцянку. Розбіжність — правило має що сказати, і
    # каже це полем `умови`, замість мовчки віддати іншу палітру.
    _умови = засмага_не_рухає_вікна(F, source, самозвіт, П.get("очі_h"))
    П["умови"] = _умови
    _слід("K-COND-02", "tan_does_not_move_family_arcs",
          значення="%s; зсув осі підтону %.2f, сімей змінилось %d"
                   % ("тримається" if _умови["тримається"] else "ЗЛАМАНО",
                      _умови["зсув_підтону"], _умови["сімей_змінилось"]),
          сила="default")
    сезон_гардеробу(П)                                  # K-COND-05
    return П

def _палітра_практична(F, source="uncontrolled", самозвіт=None, контраст_рівень=None, intent="conventional"):
    """Кістяк палітри: осі, вікна L/C і дуги сімей (ключ дуг — тон очей, R-COL-17), кольори, метал за
    знаком осі тону, найдальші, прийоми, мікроклімат рис і провенанс; `поєднання` заповнює
    `палітра_практична`.

    Чому так: метал — золото/срібло лише коли |hue| понад половину `_ДОМІНАНТА_МІН`,
    інакше «обидва»; `контраст_рівень` лежить у самій палітрі — одне джерело для
    суду образу й трійок."""
    ос = осі(F, source, самозвіт)
    П_рис = PP.палітра(F, source=source)
    к = кольори(ос, П_рис)
    очі_h = next((r["центр"] for r in П_рис["родини"]["родини"] if r["рід"] == "очі" and r.get("відношення") == "analogous"), None)
    вік = dict(L=вікно_світлоти(ос), C=вікно_хроми(ос), сім_ї=дуги_сімей(ос, очі_h),
               очі=колір_очей(F.get("очі")))
    метал = ("золото" if ос["позиція"]["hue"] > ДОМІНАНТА_МІН / 2 else
             "срібло" if ос["позиція"]["hue"] < -ДОМІНАНТА_МІН / 2 else "обидва")
    return dict(осі=ос, вікна=вік, кольори=к, метал=метал, очі_h=очі_h,
                # РІВЕНЬ КОНТРАСТУ ЛЕЖИТЬ У САМІЙ ПАЛІТРІ. Він приходить
                # сюди параметром, вирішує, які прийоми активні й якими смугами
                # будуються трійки, — і назовні не виходив. Через це `палітра_образу`
                # (суд над образом) мусив би шукати його другим каналом, а розійшовшись
                # із цим, судив би образ за одним контрастом, а пропонував трійки за
                # іншим. Одне джерело: хто має палітру, має і контраст, з яким її склали.
                контраст_рівень=контраст_рівень,
                найдальші=найдальші(ос),
                поєднання=None,   # заповнюється нижче, бо потребує кольорів
                прийоми=прийоми(ос, контраст_рівень, intent,
                                волосся_ахроматичне=any((f.get("C", 99) or 0) < cs.ACHROMATIC_C
                                                        for nm, f in PP.дані(F).items() if nm.startswith("волосся"))),
                мікроклімат=dict(нейтралі=П_рис["нейтралі"],
                                 акценти_від_очей=[r for r in П_рис["родини"]["родини"] if r["рід"] == "очі" and r.get("дуга")][:3],
                                 макіяж=П_рис["макіяж"]),
                провенанс=dict(правило_породження="палітра поділяє домінанту людини — Sci\\ART/Kalisz 2003, Lamport, JPCA; "
                                                  "Radeloff 1990: спостерігачі згодні з практиками · default як практикове рішення",
                               числа="масштаби осей, вікна, дуги сімей — T3 · hint",
                               мікроклімат="TCI «microclimate»; Zyla; Perrett 2023 (очі)"),
                статус=("це відповідь ПРАКТИКІВ на «які кольори належать мені», породжена їхнім правилом; "
                        "що вона «личить» — не виміряно; сезонного ярлика не видається (R-PC-01)"))

def рядки_у_фід(спец):
    """Рядки каталогу з практикової палітри: сім'ї у вікнах людини (кольорові слоти) і
    нейтралі за температурою (усі слоти). Ранг: сім'я очей 1, решта сімей 2, нейтралі 2."""
    П = спец.get("палітра_практична")
    if not П: return []
    Llo, Lhi = П["вікна"]["L"]; Clo, Chi = П["вікна"]["C"]
    рядки = []
    for s, v in спец["слоти"].items():
        if v.get("попередження"): continue
        sLlo, sLhi = max(v["L"][0], Llo), min(v["L"][1], Lhi)
        if sLlo > sLhi: continue
        # нейтралі за температурою палітри
        r = dict(слот=s, L_min=sLlo, L_max=sLhi, C_min=0.0, C_max=max(_РЕЄСТР.C["warm_neutral"][2], _РЕЄСТР.C["cool_neutral"][2]),
                 h_from=None, h_to=None, нейтраль=True, роль="нейтраль_палітри", ранг_риси=2,
                 джерело_тону="палітра_практична:нейтраль", чому="нейтраль у смузі світлоти палітри; температура — бік людини")
        if П["метал"] == "золото": r["b_min"] = _РЕЄСТР.C["b_нейтралі"][0]
        elif П["метал"] == "срібло": r["b_max"] = _РЕЄСТР.C["b_нейтралі"][1]
        рядки.append(r)
        # ── K-PAL-11: МЕТАЛ ФУРНІТУРИ ЙДЕ В ДОБІР ────────────────────────────
        # Рядок додається ЛИШЕ там, де метал — сама річ (`СЛОТИ_МЕТАЛУ`). Срібло
        # рядка не потребує: воно ахромат, і його вже несе нейтральний рядок вище.
        # ЗОЛОТИЙ РЯДОК СТОЇТЬ ПІД КОЖНОЮ ПАЛІТРОЮ (рішення власника, п.9 «усе можливе
        # доступне людині для вибору»). Без нього холодній жінці рядка нема, і золота каблучка
        # входила б лише фолбеком гарантії слота, тобто повз палітру. ЗМІРЯНО `проби/pal_K-PAL-11.py`
        # на самозвіті «срібло»: без рядка — 0 рядків, фурнітури крізь них 0; з рядком — золото в пулі поруч
        # зі сріблом. Холодній палітрі рядок несе `менш_ходове` — це не гейт і не
        # штраф, а мітка, з якої слот пише м'яку причину КОДОМ (заява внутрішньої мови
        # `jewellery_gold_less_usual_for_cool`), і ранг рядка вищий (= пізніший у
        # нічиїх), щоб рідший хід стояв ПОРУЧ із рештою, а не попереду. Явний вибір
        # жінки (бажання «золото») сильніший за мітку: нота тоді мовчить.
        # Рука 2 (K-PAL-11 зламане) ставить на місце цього рядка протилежний метал (`поломки`)
        if s in СЛОТИ_МЕТАЛУ:
            _ПОЛ.свідок("K-PAL-11", "pool", слот=s, метал=П["метал"])
            _рідше = П["метал"] == "срібло"
            _р = dict(слот=s, L_min=ЗОЛОТО["L"][0], L_max=ЗОЛОТО["L"][1],
                      C_min=ЗОЛОТО["C"][0], C_max=ЗОЛОТО["C"][1],
                      h_from=ЗОЛОТО["дуга"][0], h_to=ЗОЛОТО["дуга"][1],
                      нейтраль=False, метал="золото", роль="метал_палітри:золото",
                      ранг_риси=(3 if _рідше else 2), джерело_тону="палітра_практична:метал",
                      чому="фурнітура: метал палітри — %s (K-PAL-11)" % П["метал"])
            if _рідше: _р["менш_ходове"] = True
            рядок = _ПОЛ.злам("K-PAL-11", "рядок", _р, слот=s, метал=П["метал"])
            рядки.append(рядок)
            if рядок is _р:
                _слід("K-PAL-11", "palette_metal_in_selection_window", значення=П["метал"])
        if "сім_я" in v: continue
        for сім, arcs in П["вікна"]["сім_ї"].items():
            for a in arcs:
                # РАНГ 1 — ЛИШЕ РЯДОК СІМ'Ї ОЧЕЙ (2.14-А): він добирає речі вердиктом відлуння райдужки
                # (`колір_відношення.сила_відлуння_очей` через `очі_запис`), тож річ, що відлунює очі, входить
                # саме ним і дістає ранг 1. Інакше ранг 1 діставала б і вся сім'я палітри, чий центр за ±30° CIELAB від
                # очей: карим очам h55 — жовта-тепла (центр 85, 72° кола, `сила_відлуння_очей` ≈ 0) цілком.
                очі = сім == "очі"
                # сім'я очей добирається тим самим вердиктом, що K-PAL-02/13: запис райдужки в рядку
                _очі = dict(очі_запис=П["вікна"]["очі"]) if сім == "очі" and П["вікна"].get("очі") else {}
                рядки.append(dict(слот=s, L_min=sLlo, L_max=sLhi, C_min=max(v["C"][0], Clo), C_max=min(v["C"][1], Chi),
                                  h_from=a[0], h_to=a[1], нейтраль=False, роль="сім_я_палітри:%s" % сім, **_очі,
                                  ранг_риси=(1 if очі else 2), джерело_тону="палітра_практична:%s" % сім,
                                  чому=("сім'я «%s» у версії %s людини; %s" %
                                        (сім, {"тепла": "теплій", "холодна": "холодній"}.get(версія_дуги(сім, a), "своїй"),
                                         "сім'я очей — ранг 1" if очі else "ранг 2"))))
    рядки = [q for q in рядки if q["C_min"] <= q["C_max"]]
    рядки.sort(key=lambda q: q["ранг_риси"])
    return рядки

# ── ОБІЦЯНКА СХЕМИ ПЕРЕВІРЯЄТЬСЯ, А НЕ ЛИШЕ ОГОЛОШУЄТЬСЯ (K-COL-03) ──────────
# ЧОМУ ПЕРЕВІРКА (спостереження власника). Жінка обрала «нейтрали+акцент» —
# «нейтралі людини + один акцент». Продукт видав образ із трьох речей і образ із
# п'яти, в обох жодної кольорової речі. Код не сказав нічого: `pipeline.акцент_образу`
# (K-PAL-18) говорить ПОСЛОТОВО і лише там, де акцентний слот в образі Є і його річ
# має ВИМІРЯНУ низьку хрому, а зведену знахідку «жоден акцентний слот не несе хроми»
# там свідомо зняли — вона виходила з `слот=None`, ні до чого не чіплялась і гинула
# в графі. Отже обіцянка, яку система дала жінці на екрані палітри, не перевірялась
# ніде: образ без єдиної барви проходив як «спокійний».
# ЧОМУ K-COL-03, А НЕ НОВЕ ПРАВИЛО. Корпус K-COL-03 і є цією обіцянкою й називає
# саме цей ризик: «Neutral base + accent — the reliable default AND THE PRIMARY
# GENERATOR OF BLANDNESS, therefore subject to the interest floor». Правило вже
# описує ситуацію — йому бракувало ВХОДУ, а не тексту.
# ЧОМУ РЕПЛІКА, А НЕ ГЕЙТ. Корпус дає `FORCE: default` (запис у
# `реєстр_правил.ПОЛІТИКА_РЕГІСТРУ`), і регістр рахується звідти. Невиконана
# схема — те, що жінці КАЖУТЬ; забирати в неї образ за це правило корпусу не дає.
# ЧОМУ ТУТ, А НЕ В `pipeline`. `pipeline` тримає паралельна сесія; та й місце
# правильніше: схеми, їхні сім'ї та обіцянки живуть у цьому модулі, а `pipeline`
# лише збирає вердикт і кличе цю функцію одним рядком.
def хроматична(lab):
    """(сім'я, C*) якщо річ читається КОЛЬОРОМ, або None — нейтраль чи не виміряно.

    Межа «колір проти нейтралі» береться з `колір_образу.нейтраль` — того самого
    визначення, яким судить решта системи (K-COL-06), а не другим порогом тут."""
    if not lab or len(lab) < 3:
        return None
    if _КР.нейтраль(lab):
        return None
    # Довжину `lab` перевірено вище, `нейтраль(lab)` уже порахувала
    # цей самий Lab; не-число всередині — зіпсований запис, який має впасти в
    # `bridge.виклик`, а не стати «нейтраллю».
    _L, C, _h = cs.lch(lab)
    # СІМ'Я — ЗА `колір_образу.FAMILIES`, А НЕ ЗА `СІМ_Ї` ЦЬОГО МОДУЛЯ. Тут
    # рахується, СКІЛЬКИ РІЗНИХ кольорів в образі, а для лічби потрібне РОЗБИТТЯ
    # кола тону. `СІМ_Ї` практиків розбиттям не є за побудовою (дуги
    # перетинаються, між ними є проміжки), тож два тони з проміжку зійшлись би в
    # одну «невизначену» сім'ю, а сусідні — розійшлись би за порядком оголошення.
    # `FAMILIES` — рівно те розбиття, яким судить решта системи.
    return (_КР.сім_я(lab), C)


def lab_повної(повна):
    """Lab речі з каталогу, коли колір — точка (`колір_річ.точка_кольору`: `lab`, інакше `hex`);
    None — колір зі слова (центр вікна — не вимір) чи не виміряно (хибний hex — теж).
    Чи є в речі колір узагалі (точка чи вікно) — `_є_колір`."""
    return _КР.точка_кольору(повна)


def є_колір(повна):
    """True — у речі є колір: точка (`_lab_повної`) чи вікно слова (`колір_річ.межі_кольору`)."""
    return lab_повної(повна) is not None or _КР.межі_кольору(повна) is not None


_МЕТАЛ_ВІКНА = {}


def метал_меж(x, слот=None, тип=None):
    """«так» / «ні» / «невідомо»: чи колір речі чи елемента читається металом (`метал_речі`). Точка —
    сама точка; колір зі слова — сіткою вікна (`колір_річ.точки_вікна`): металом усі точки — «так»,
    жодна — «ні», інакше «невідомо» (центр вікна — не вимір: металом був би «кемел» і не був би
    «золотий», залежно від того, куди падав центр; вікно сягає вікна металу в 38 слів лексикону з 56).
    «ні» і тоді, коли слот не фурнітура; None — кольору нема. Вікон — стільки, скільки слів: кеш."""
    т = _КР.точка_кольору(x)
    if т is None and _КР.межі_кольору(x) is None:
        return None
    if слот is not None and not слот_металу(слот, тип):
        return "ні"
    if т is not None:
        return "так" if метал_речі(т, слот, тип) else "ні"
    м = _КР.межі_кольору(x)
    if м not in _МЕТАЛ_ВІКНА:
        мм = {bool(метал_речі(p)) for p in _КР.точки_вікна(м)}
        _МЕТАЛ_ВІКНА[м] = "так" if мм == {True} else "ні" if мм == {False} else "невідомо"
    return _МЕТАЛ_ВІКНА[м]


# ── «НЕЙТРАЛЬНИЙ» — ЛИШЕ КОЛИ Й ВИМІР, І СЛОВО КРАМНИЦІ КАЖУТЬ «НЕЙТРАЛЬ» (СХЕМА-КАРТКА) ──
# Приклад: «образ вийшов суто нейтральним» стояв над «Піджак однобортний
# ніжно-рожевий» і «Туфлі Sergio Rossi блакитні» (ж7_церква, ж1_робота) — вимір читав їх нейтраллю
# (низька хрома; холодний коридор `колір_образу.нейтраль` ковтає світло-блакитне з C* 23), а крамниця
# називає колір, і жінка бачить колір на фото. Коли два свідки розходяться, код «нейтраль» не
# стверджує — та сама політика, що «невимір — не провал». Слово береться з поля кольору й назви
# (`verify.назва_кольору`), тон слова — сім'єю словника (`verify.слово_називає_тон`).
def несе_колір(повна):
    """«вимір» / «слово» / None — чи річ несе колір за виміром АБО за словом крамниці.

    Вимір прикраси — і колір поза металом (`колір_вставки`): емаль чи камінь.
    Прикраса, чий колір знає лише слово металу (`_колір_невідомий`), — None: центр вікна
    «золотий» хроматичний (C* 37), але це не вимір, а «золотий»/«білий» у полі кольору й назві —
    слово металу, не свідок кольору (метал — матеріал, не колір, як в
    `outfit.елементи`). Такий колір лишається невідомим, а не акцентом схеми."""
    if колір_невідомий(повна) or колір_металу(повна):
        return None
    if повна.get("метал"):
        return "вимір"
    lab = lab_повної(повна)
    if хроматична_вставка(повна):
        return "вимір"
    if lab and хроматична(lab):
        return "вимір"
    # КОЛІР ЗІ СЛОВА — СВІДОК СЛОВА, НЕ ВИМІРУ: з 49 кольорових речей фіналів рук 1–2
    # колір 29 — дефолтний hex слова (`#39873a` «зелений» 17 разів); «вийшла» на них стоїть словом
    # крамниці, і звіт мусить це бачити (`схема_жінці.за_словом`). Колір слова — не центр
    # вікна, а межі: слово несе колір, коли його вікно не вся нейтраль K-COL-06
    # («ні» чи «невідомо»: «увесь нейтральний» на ньому не доведено)
    if lab is None and _КР.межі_кольору(повна) is not None and _КР.нейтраль_меж(повна) != "так":
        return "слово"
    for поле in ("колір_назва", "назва"):
        сл = V.назва_кольору(str(повна.get(поле) or ""))
        if сл and V.слово_називає_тон(сл):
            return "слово"
    return None


# ── КОЛІР ПРИКРАСИ — З КАДРУ, А НЕ ЗІ СЛОВА МЕТАЛУ (СХЕМА-КАРТКА) ──
# Приклад ж4_робота_живіт: «Срібні сережки з емаллю та кристалами» читались «виміряною
# нейтраллю» — `lab` запису був центром вікна слова «срібний», — і картка р2 радила «познач
# „не це“» саме на сережки, які на фото несуть м'ятну емаль. Два входи, обидва — числа:
#   · `колір_вставки` (`фід_збагачення.колір_вставки`) — виміряні кластери кадру поза вікнами
#     металу з частками; хроматичний кластер — річ несе колір (`_несе_колір`, «вимір»);
#   · коли кадру нема (збагачення v2 не дійшло), колір прикраси знає лише СЛОВО металу, а
#     воно — про метал, не про всю поверхню: така річ не «виміряна нейтраль» (`_колір_невідомий`).
def хроматична_вставка(повна):
    """(сім'я, C*, Lab) найбільшого хроматичного кластера поза металом — або None."""
    for в in sorted(повна.get("колір_вставки") or (), key=lambda в: -float(в.get("частка") or 0)):
        т = _КР.точка_кольору(в)      # кластер кадру — вимір
        х = хроматична(т)
        if х:
            return (*х, т)
    return None


def колір_металу(повна):
    """True — колір речі чи елемента є металом прикраси: `метал` у слоті фурнітури (`СЛОТИ_МЕТАЛУ`;
    пряжка пояса чи сумки кольору речі не дає) і без хроматичного кластера поза металом
    (`_хроматична_вставка`); коли кластерів не міряли (елемент образу, запис без збагачення v2) —
    коли колір знає лише слово (воно тут — слово металу) або сам вимір читається металом (`метал_речі`). Такий колір — матеріал, не колір схеми: його
    судить температура людини (K-PAL-11), а не дуга схеми (K-PAL-03) чи бік b* очей (R-COL-16).
    Одне означення для `_несе_колір`, дуги схеми пулу й суду (`palettes.тримає_дугу_схеми`) і
    R-COL-16."""
    if not (isinstance(повна, dict) and повна.get("метал")):
        return False
    слот, тип = повна.get("слот"), повна.get("тип")
    if слот is not None and not слот_металу(слот, тип):
        return False
    if "колір_вставки" in повна:
        return not хроматична_вставка(повна)
    if повна.get("колір_не_вимір"):
        return True             # колір знає лише слово, а в прикраси з металом це слово металу
    return метал_меж(повна, слот, тип) == "так"       # сюди доходить лише точка: вікно — гілкою вище


def колір_невідомий(повна):
    """True — колір прикраси з металом знає лише слово металу: кластерів кадру нема, колір — вікно
    слова (`колір_не_вимір`), і воно може бути металом (`метал_меж` зі слотом «так» чи «невідомо»;
    не центр вікна)."""
    if not (повна.get("метал") and повна.get("колір_не_вимір")) or повна.get("колір_вставки"):
        return False
    return метал_меж(повна, повна.get("слот"), повна.get("тип")) in ("так", "невідомо")


