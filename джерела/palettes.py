def рядки_у_фід(спец):
    """Рядки каталогу з практикової палітри: сім'ї у вікнах людини (кольорові слоти) і
    нейтралі за температурою (усі слоти). Ранг: сім'я очей 1, решта сімей 2, нейтралі 2."""
    П = спец.get("палітра_практична")
    if not П: return []
    Llo, Lhi = П["вікна"]["L"]; Clo, Chi = П["вікна"]["C"]
    очі_h = [r["центр"] for r in П["мікроклімат"]["акценти_від_очей"] if r.get("відношення") == "analogous"]
    рядки = []
    for s, v in спец["слоти"].items():
        if v.get("попередження"): continue
        sLlo, sLhi = max(v["L"][0], Llo), min(v["L"][1], Lhi)
        if sLlo > sLhi: continue
        # нейтралі за температурою палітри
        r = dict(слот=s, L_min=sLlo, L_max=sLhi, C_min=0.0, C_max=max(_РЕЄСТР.C["warm_neutral"][2], _РЕЄСТР.C["cool_neutral"][2]),
                 h_from=None, h_to=None, нейтраль=True, роль="нейтраль_палітри", ранг_риси=2,
                 джерело_тону="палітра_практична:нейтраль", чому="нейтраль у смузі світлоти палітри; температура — бік людини")
        if П["метал"] == "золото": r["b_min"] = _РЕЄСТР.C["b_нейтралі"][0]
        elif П["метал"] == "срібло": r["b_max"] = _РЕЄСТР.C["b_нейтралі"][1]
        рядки.append(r)
        # ── K-PAL-11: МЕТАЛ ФУРНІТУРИ ЙДЕ В ДОБІР ────────────────────────────
        # Рядок додається ЛИШЕ там, де метал — сама річ (`СЛОТИ_МЕТАЛУ`). Срібло
        # рядка не потребує: воно ахромат, і його вже несе нейтральний рядок вище.
        # ЗОЛОТИЙ РЯДОК СТОЇТЬ ПІД КОЖНОЮ ПАЛІТРОЮ (рядок 257, рішення власника
        # 01.10.2026, п.9 «усе можливе доступне людині для вибору»). Доти холодній
        # жінці рядка не було, і золота каблучка входила лише фолбеком гарантії слота,
        # тобто повз палітру. ЗМІРЯНО `проби/pal_K-PAL-11.py` на самозвіті «срібло»:
        # до — рядків 0, фурнітури крізь них 0; після — рядок є, золото в пулі поруч
        # зі сріблом. Холодній палітрі рядок несе `менш_ходове` — це не гейт і не
        # штраф, а мітка, з якої слот пише м'яку причину КОДОМ (заява внутрішньої мови
        # `jewellery_gold_less_usual_for_cool`), і ранг рядка вищий (= пізніший у
        # нічиїх), щоб рідший хід стояв ПОРУЧ із рештою, а не попереду. Явний вибір
        # жінки (бажання «золото») сильніший за мітку: нота тоді мовчить.
        # Р2-2а: тема «прикраси» вимкнена руці 2 — металу палітри в доборі нема (тінь);
        # рука 1 під стеженням рядок має, а дія записується
        import правило_руки2 as _ПР2
        if s in СЛОТИ_МЕТАЛУ and not _ПР2.торкнулось("K-PAL-11", "pool", слот=s, метал=П["метал"]):
            _рідше = П["метал"] == "срібло"
            _р = dict(слот=s, L_min=ЗОЛОТО["L"][0], L_max=ЗОЛОТО["L"][1],
                      C_min=ЗОЛОТО["C"][0], C_max=ЗОЛОТО["C"][1],
                      h_from=ЗОЛОТО["дуга"][0], h_to=ЗОЛОТО["дуга"][1],
                      нейтраль=False, метал="золото", роль="метал_палітри:золото",
                      ранг_риси=(3 if _рідше else 2), джерело_тону="палітра_практична:метал",
                      чому="фурнітура: метал палітри — %s (K-PAL-11)" % П["метал"])
            if _рідше: _р["менш_ходове"] = True
            рядки.append(_р)
            _слід("K-PAL-11", "метал палітри у вікні добору", значення=П["метал"])
        if "сім_я" in v: continue
        for сім, arcs in П["вікна"]["сім_ї"].items():
            for a in arcs:
                c = (a[0] + ((a[1] - a[0]) % 360) / 2) % 360
                очі = (сім == "очі") or any(abs((c - h + 180) % 360 - 180) <= 30 for h in очі_h)
                рядки.append(dict(слот=s, L_min=sLlo, L_max=sLhi, C_min=max(v["C"][0], Clo), C_max=min(v["C"][1], Chi),
                                  h_from=a[0], h_to=a[1], нейтраль=False, роль="сім_я_палітри:%s" % сім,
                                  ранг_риси=(1 if очі else 2), джерело_тону="палітра_практична:%s" % сім,
                                  чому=("сім'я «%s» у версії %s людини; %s" %
                                        (сім, "теплій" if 0 <= c < 180 else "холодній",
                                         "збігається з сім'єю очей — ранг 1" if очі else "ранг 2"))))
    рядки = [q for q in рядки if q["C_min"] <= q["C_max"]]
    рядки.sort(key=lambda q: q["ранг_риси"])
    return рядки

# ── ОБІЦЯНКА СХЕМИ ПЕРЕВІРЯЄТЬСЯ, А НЕ ЛИШЕ ОГОЛОШУЄТЬСЯ (K-COL-03) ──────────
# ЩО БУЛО (спостереження власника 19.09.2026). Жінка обрала «нейтрали+акцент» —
# «нейтралі людини + один акцент». Продукт видав образ із трьох речей і образ із
# п'яти, в обох жодної кольорової речі. Код не сказав нічого: `pipeline.акцент_образу`
# (K-PAL-18) говорить ПОСЛОТОВО і лише там, де акцентний слот в образі Є і його річ
# має ВИМІРЯНУ низьку хрому, а зведену знахідку «жоден акцентний слот не несе хроми»
# там свідомо зняли — вона виходила з `слот=None`, ні до чого не чіплялась і гинула
# в графі. Отже обіцянка, яку система дала жінці на екрані палітри, не перевірялась
# ніде: образ без єдиної барви проходив як «спокійний».
# ЧОМУ K-COL-03, А НЕ НОВЕ ПРАВИЛО. Корпус K-COL-03 і є цією обіцянкою й називає
# саме цей ризик: «Neutral base + accent — the reliable default AND THE PRIMARY
# GENERATOR OF BLANDNESS, therefore subject to the interest floor». Правило вже
# описує ситуацію — йому бракувало ВХОДУ, а не тексту.
# ЧОМУ РЕПЛІКА, А НЕ ГЕЙТ. Корпус дає `FORCE: default` (запис у
# `реєстр_правил.ПОЛІТИКА_РЕГІСТРУ`), і регістр рахується звідти. Невиконана
# схема — те, що жінці КАЖУТЬ; забирати в неї образ за це правило корпусу не дає.
# ЧОМУ ТУТ, А НЕ В `pipeline`. `pipeline` тримає паралельна сесія; та й місце
# правильніше: схеми, їхні сім'ї та обіцянки живуть у цьому модулі, а `pipeline`
# лише збирає вердикт і кличе цю функцію одним рядком.
def _хроматична(lab):
    """(сім'я, C*) якщо річ читається КОЛЬОРОМ, або None — нейтраль чи не виміряно.

    Межа «колір проти нейтралі» береться з `колір_образу.нейтраль` — того самого
    визначення, яким судить решта системи (K-COL-06), а не другим порогом тут."""
    if not lab or len(lab) < 3:
        return None
    import колір_образу as _КО
    if _КО.нейтраль(lab):
        return None
    # п.14 (20.09.2026): довжину `lab` перевірено вище, `нейтраль(lab)` уже порахувала
    # цей самий Lab; не-число всередині — зіпсований запис, який має впасти в
    # `bridge.виклик`, а не стати «нейтраллю».
    _L, C, _h = cs.lch(lab)
    # СІМ'Я — ЗА `колір_образу.FAMILIES`, А НЕ ЗА `СІМ_Ї` ЦЬОГО МОДУЛЯ. Тут
    # рахується, СКІЛЬКИ РІЗНИХ кольорів в образі, а для лічби потрібне РОЗБИТТЯ
    # кола тону. `СІМ_Ї` практиків розбиттям не є за побудовою (дуги
    # перетинаються, між ними є проміжки), тож два тони з проміжку зійшлись би в
    # одну «невизначену» сім'ю, а сусідні — розійшлись би за порядком оголошення.
    # `FAMILIES` — рівно те розбиття, яким судить решта системи.
    return (_КО.сім_я(lab), C)


def _lab_повної(повна):
    """Lab речі з каталогу: `lab`, інакше з `hex`; None — колір не виміряно (хибний hex — теж)."""
    lab = повна.get("lab")
    if not lab and повна.get("hex"):
        try:
            lab = cs.hx(повна["hex"])
        except ValueError:
            lab = None
    return lab or None


# ── «НЕЙТРАЛЬНИЙ» — ЛИШЕ КОЛИ Й ВИМІР, І СЛОВО КРАМНИЦІ КАЖУТЬ «НЕЙТРАЛЬ» (СХЕМА-КАРТКА, 02.10.2026) ──
# Розбір 02.10 (рядки 1292, 1455): «образ вийшов суто нейтральним» стояв над «Піджак однобортний
# ніжно-рожевий» і «Туфлі Sergio Rossi блакитні» (ж7_церква, ж1_робота) — вимір читав їх нейтраллю
# (низька хрома; холодний коридор `колір_образу.нейтраль` ковтає світло-блакитне з C* 23), а крамниця
# називає колір, і жінка бачить колір на фото. Коли два свідки розходяться, код «нейтраль» не
# стверджує — та сама політика, що «невимір — не провал». Слово береться з поля кольору й назви
# (`verify.назва_кольору`), тон слова — сім'єю словника (`verify.слово_називає_тон`).
def _несе_колір(повна):
    """«вимір» / «слово» / None — чи річ несе колір за виміром АБО за словом крамниці.

    Вимір прикраси — і колір поза металом (`колір_вставки`, рядок 1480): емаль чи камінь.
    Прикраса, чий колір знає лише слово металу (`_колір_невідомий`), — None: центр вікна
    «золотий» хроматичний (C* 37), але це не вимір, а «золотий»/«білий» у полі кольору й назві —
    слово металу, не свідок кольору (рядок 1682; метал — матеріал, не колір, як в
    `outfit.елементи`). Такий колір лишається невідомим, а не акцентом схеми."""
    if _колір_невідомий(повна):
        return None
    if повна.get("метал"):
        return "вимір" if _хроматична_вставка(повна) else None
    lab = _lab_повної(повна)
    if (lab and _хроматична(lab)) or _хроматична_вставка(повна):
        return "вимір"
    for поле in ("колір_назва", "назва"):
        сл = V.назва_кольору(str(повна.get(поле) or ""))
        if сл and V.слово_називає_тон(сл):
            return "слово"
    return None


# ── КОЛІР ПРИКРАСИ — З КАДРУ, А НЕ ЗІ СЛОВА МЕТАЛУ (СХЕМА-КАРТКА, рядок 1480, 07.10.2026) ──
# Живий ПІСЛЯ ж4_робота_живіт v1: «Срібні сережки з емаллю та кристалами» читались «виміряною
# нейтраллю» — `lab` запису був центром вікна слова «срібний», — і картка р2 радила «познач
# „не це“» саме на сережки, які на фото несуть м'ятну емаль. Два входи, обидва — числа:
#   · `колір_вставки` (`фід_збагачення.колір_вставки`) — виміряні кластери кадру поза вікнами
#     металу з частками; хроматичний кластер — річ несе колір (`_несе_колір`, «вимір»);
#   · коли кадру нема (збагачення v2 не дійшло), колір прикраси знає лише СЛОВО металу, а
#     воно — про метал, не про всю поверхню: така річ не «виміряна нейтраль» (`_колір_невідомий`).
def _хроматична_вставка(повна):
    """(сім'я, C*, Lab) найбільшого хроматичного кластера поза металом — або None."""
    for в in sorted(повна.get("колір_вставки") or (), key=lambda в: -float(в.get("частка") or 0)):
        х = _хроматична(в.get("lab"))
        if х:
            return (*х, в["lab"])
    return None


def _колір_невідомий(повна):
    """True — колір прикраси з металом знає лише слово металу: кластерів кадру нема, `lab` —
    центр вікна слова (`колір_не_вимір`), і він читається металом (`метал_речі` зі слотом)."""
    if not (повна.get("метал") and повна.get("колір_не_вимір")) or повна.get("колір_вставки"):
        return False
    lab = _lab_повної(повна)
    return bool(lab and метал_речі(lab, повна.get("слот")))


