# ── ТОНАЛЬНА — ОДИН ТОН НА РЕЧАХ, А НЕ «ХОЧ ЩОСЬ КОЛЬОРОВЕ» (рядок 1403) ─────────
# Екран обіцяє «один тон на всіх речах із маленькими кроками за світлотою», а «схема вийшла»
# рахувалась так само, як для «нейтрали+акцент»: будь-яка кольорова річ. Розбір 02.10: з 15 «так»
