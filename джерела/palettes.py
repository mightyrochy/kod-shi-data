# ── ЩО З ПАЛІТРИ ЇДЕ ДО МОДЕЛІ Й У ОПИС ──────────────────────────────────────
# ЧОМУ ОКРЕМА ФУНКЦІЯ, А НЕ ШМАТОК `людина_для_пакета`. Те саме треба двом
# викликам — пакету (руки 1–2) і опису (рука 4), — і два склади того самого
# розійшлись би на першій правці одного з них: жінці сказали б про метал в описі
# і не сказали б у пакеті, або навпаки. Тут один склад.
# ЧИСЕЛ НЕМА НАВМИСНО. Промпт від початку забороняє моделі говорити нашою шкалою
# («не називай чисел світлоти»), а `словами` вже має для кожної осі СЛОВО. Тому
# сюди їдуть слова прийомів і назви кольорів із hex — те, чим модель однаково
# говорить із жінкою, — і жодного L*, C* чи позиції осі.
def для_пакета(П, поєднань=3):
    """Метал, найдальші кольори, кілька поєднань і активні прийоми — словами.

    K-PAL-11 (метал), K-PAL-14 (найдальші), K-PAL-15 (поєднання), K-PAL-02…13
    (прийоми, доступні саме цьому типові контрасту). Усі чотири доти рахувались і
    не доїжджали: пакет знав про палітру лише схему, ролі слотів, нейтралі й
    акценти, а `словами` (де все це є) ішло тільки в бриф для людини.
    """
    if not П:
        return {}
    вих = {}
    м = П.get("метал")
    if м:
        вих["метал"] = метал_словами(м)
    д = (П.get("найдальші") or {}).get("словами")
    if д and "нема вираженої осі" not in д:
        вих["найдальші"] = д
    трійки = []
    for п in (П.get("поєднання") or [])[:поєднань]:
        трійки.append(dict(прийом=str(п.get("прийом") or ""),
                           кольори=[" ".join(x for x in (к.get("назва"), к.get("hex")) if x)
                                    for к in (п.get("кольори") or [])]))
    if трійки:
        вих["поєднання"] = трійки
    акт = []
    for x in (П.get("прийоми") or []):
        if not x.get("активний"):
            continue
        п = ПРИЙОМИ.get(x["прийом"]) or {}
        т = str(п.get("суть_моделі") or x.get("суть") or "")
        # ГЕЙТ, А НЕ ВІРА: ID корпусу в тексті для моделі — витік (гейт §41), і
        # `_без_ід` знімає його, ламаючи речення. Прийом, чия суть посилається на
        # чуже правило, мусить нести `суть_моделі`; мовчазного пропуску тут нема.
        assert not _re_pal.search(т), ("прийом «%s»: суть для моделі несе ID корпусу" % x["прийом"])
        акт.append(dict(прийом=str(x["прийом"]), суть=т))
    if акт:
        вих["прийоми"] = акт
    # ── ТЕ, ЩО ВЕЗЛА ЛИШЕ ПРОЗА `словами(П)` (П-5, аудит/ПРОДУКТ.md п.12) ──
    # `словами` складала вісім речень українською, і через бриф абзац доїжджав у
    # `style_rules` АНГЛІЙСЬКОГО промпта як є. Частина її фактів у пакеті вже була (метал,
    # найдальші, поєднання, прийоми, нейтралі й акценти назвами) — а частина жила ТІЛЬКИ в
    # прозі: осі, домінанта, вікно, сім'ї акцентів, температура й світлота нейтралей, сезон
    # гардероба, застереження про калібрування. Тепер вони їдуть кодами й числами.
    # ЧОМУ КЛЮЧІ ТУТ АНГЛІЙСЬКІ, А СУСІДНІ — КИРИЛИЦЕЮ. `дріт_моделі.палітра` перекладає
    # свій НАЗВАНИЙ перелік ключів («метал» → metal…), а ключ, якого в переліку нема,
    # пропускає в дріт ЯК Є. Дописати переклад не можна: `дріт_моделі.py` цей наряд не
    # чіпає (К-3). Тому нові поля названі так, як мають стояти в дроті, — інакше в
    # англійському промпті стали б кириличні ключі (так туди й потрапила `основа` з
    # `пакет_моделі`: ключі «слово»/«hex»/«джерело» — це той самий витік, він лишається).
    ос = П.get("осі") or {}
    if ос.get("коди"):
        вих["axes"] = {"sides": dict(ос["коди"]), "positions": dict(ос.get("позиція") or {}),
                       "source_hue": ос.get("джерело_код")}
        for к, п in (("dominant", "домінанта"), ("secondary", "вторинна")):
            if ос.get(п):
                вих["axes"][к] = ос[п]
    вк = П.get("вікна") or {}
    if вк.get("L") and вк.get("C"):
        вих["window"] = {"lightness": [round(x) for x in вк["L"]],
                         "chroma": [round(x) for x in вк["C"]]}
    сім, сез, нт = {}, {"autumn_winter": [], "spring_summer": []}, []
    for c in (П.get("кольори") or []):
        # назви кольорів лишаються словами лексикону: їх жінка бачить у підписі на
        # картці — той самий виняток, що для `нейтралі` й `акценти` вище
        if c.get("роль") == "колір" and c.get("сім_я"):
            if c.get("назва") not in сім.setdefault(c["сім_я"], []):
                сім[c["сім_я"]].append(c.get("назва"))
        else:
            нт.append({"name": c.get("назва"), "hex": c.get("hex"),
                       "temperature": _ВМ.код_або_невідомо("colour_temperature", c.get("температура")),
                       "lightness": (round(c["L"]) if c.get("L") is not None else None)})
        к = {"осінь-зима": "autumn_winter", "весна-літо": "spring_summer"}.get(c.get("сезон_гардеробу"))
        if к and c.get("назва") and c["назва"] not in сез[к]:
            сез[к].append(c["назва"])
    if сім:
        вих["accent_families"] = [{"family": _ВМ.код_або_невідомо("palette_family", с), "colors": н}
                                  for с, н in сім.items()]
    if нт:
        вих["neutral_axes"] = list({(x["name"], x["hex"]): x for x in нт}.values())
    if сез["autumn_winter"] or сез["spring_summer"]:
        вих["wardrobe_season"] = {k: v[:6] for k, v in сез.items() if v}
    # застереження `статус` було реченням («усі межі T3, не калібровані; вихід придатний як
    # фільтр фіду, не як обіцянка, що така річ у каталозі є») — тепер код
    вих["calibration"] = "t3_uncalibrated_filter_not_promise"
    return вих


# ── `словами(П)` ЗНЯТА (П-5, аудит/ПРОДУКТ.md п.12) ─────────────────────
# Вісім речень українською — «Ваші осі: світлота — світла (−0.62)…», «Вікно палітри:
# світлота 44–74, хрома 8–26; метал — срібло», «Сім'ї у вашій версії: …» — складав КОД,
# і через `палітра_специфікація.палітра_практична_словами` → `brief.дод("палітра", …)`
# абзац доїжджав у `style_rules` АНГЛІЙСЬКОГО промпта функціональної моделі як є.
# Тепер ті самі факти їдуть кодами й числами з `для_пакета` (`axes`, `window`,
# `accent_families`, `neutral_axes`, `wardrobe_season`, `calibration` поруч із metal,
# farthest, combinations, techniques), а речення про палітру складає модель.
# `палітра_словами` (палітра особи) знято заразом: читача воно не мало НІ ОДНОГО.


def слоти_акценту_схеми(речі, спец_слоти):
    """{слот} — де схема палітри оголосила фокус: слот із роллю «акцент», чия річ НЕСЕ
    тон `дуга_тону` слота (`колір_річ.несе_тон`; схема без дуги — будь-яка хроматична
    річ у слоті). Вхід — речі образу й `спец_слоти` суду (`міст_пакет._спец_слоти`:
    слоти верхнім рівнем, службові ключі на «_»). Той самий критерій, що «scheme» у
    `групи_фокусів`, — для K-COL-05, який судить речі, а не елементи кольору."""
    вих = set()
    for с, сп in (спец_слоти or {}).items():
        if str(с).startswith("_") or not isinstance(сп, dict) or сп.get("роль") != "акцент":
            continue
        for r in речі or ():
            if r.get("слот") != с:
                continue
            if сп.get("дуга_тону"):
                if _КР.несе_тон(r, сп["дуга_тону"]):
                    вих.add(с)
            elif r.get("hex"):
                # хроматична річ: точка — не нейтраль; колір зі слова — межами: нейтраллю
                # не є жодна точка вікна
                т = _КР.точка_кольору(r)
                if (not _КР.нейтраль(т)) if т is not None else _КР.нейтраль_меж(r) == "ні":
                    вих.add(с)
    return вих


def тримає_дугу_схеми(x, дуги):
    """«так» / «ні» / «невідомо» / None — чи колір речі `x` лежить у дугах схеми слота.

    «так» — метал без кольорової вставки, нейтраль або тон у дузі (сила від
    `колір_відношення.КІНЕЦЬ_ЗГАСАННЯ`; вікно слова — усе вікно); «ні» — жодна точка вікна не
    в дузі й річ не може бути нейтраллю; «невідомо» — вікно слова лише частково в дузі або
    «можливо нейтраль»; None — кольору нема чи слот без дуги."""
    if колір_металу(x):
        return "так"
    нт = нейтраль_меж(x)
    if нт is None:
        return None
    if нт == "так":
        return "так"
    if not дуги:
        return None
    в = у_дугах_кола(x, дуги, до_кінця_згасання=True)
    return "невідомо" if в == "ні" and нт == "невідомо" else в


# ─── ЄДИНЕ ВИЗНАЧЕННЯ РІВНЯ КОНТРАСТУ ───────────────────────────────────────
# Розбір знайшов ТРИ різні версії цих порогів у системі: тут 22/45, у profile.контраст
# (шлях із макіяжем) 20/40, і третю в коментарі palette. А palette.розвилка ключується
# САМЕ на рівні — отже людина потрапляла в різні гілки схем залежно від того, яким
# шляхом прийшла. Тепер число одне, і хто його читає, читає звідси.
РІВНІ_КОНТРАСТУ = (22.0, 45.0)      # T3, некалібровані; напрям зсуву — T2 (Candille 2012)


def рівень_контрасту(gap):
    """Розрив світлоти волосся↔шкіри (gap) → «низький» / «середній» / «високий».

    ЄДИНЕ визначення рівня на всю систему (абзац вище): порогів було три різні —
    тут 22/45, у `profile.контраст` 20/40 і ще одні в коментарі `palette`, — а
    `palette.розвилка` ключується САМЕ на рівні, тож людина потрапляла в різні
    гілки схем залежно від шляху, яким прийшла. Самі числа — T3, некалібровані."""
    lo, hi = РІВНІ_КОНТРАСТУ
    return "низький" if gap < lo else ("середній" if gap < hi else "високий")


# ─────────────────────────── ОСОБА ───────────────────────────
def контраст_особи(F, source="uncontrolled"):
    """K-CLR-01 вісь 1 + гейтинг K-PC-05.
    Волосся↔шкіра — несуча пара (Lamport: волосся важить у зчитуванні value найбільше [H]).
    Очі НЕ входять у контраст образу: площа мала; вони живуть у вісі colour contrast.
    (Інакше темні очі робили б попелясту блондинку «висококонтрастною» — хибно за корпусом.)

    ДЖЕРЕЛО: РЕГІОНИ — первинне (єдина точка істини для геометрії рис); пряме обчислення з F —
    ЗАПАСНЕ (той самий метод: волосся↔шкіра L-дельта), коли регіони недоступні. Обидва однакові."""
    R = reliability(source)
    шк = F.get("шкіра")
    hair = [v for k, v in F.items() if k.startswith("волосся") and not k.startswith("_")]
    if not шк or not hair:
        return dict(доступно=False, чому="нема шкіри або волосся у профілі")
    Lh = sum(h["L"] for h in hair)/len(hair)
    # розкид волосся — НЕПЕРЕРВНЕ СКВ (не max−min): усі під-риси волосся, зважено. σ, не діапазон.
    розкид_волосся = round(_розсіяння([h["L"] for h in hair])[0] or 0.0, 1)
    # ── РІШЕННЯ ПРО ІМ'Я `розкид` НА КАРТЦІ ОСОБИ (Н-outfit-1-086, записано) ──
    # `_розкид(*nf, особа)` брав `особа` в аргументи й МОВЧКИ її не рахував: картка
    # людини поля `розкид` не мала взагалі, тож `max()` завжди бігав лише по речах.
    # Поле тепер є — але мусить нести ТУ САМУ величину, що й у речах, бо це той самий
    # `max()`. У речах `розкид` = `extract._se_медоїда`, тобто ПОХИБКА ЦЕНТРАЛЬНОЇ
    # ОЦІНКИ L* зони (~1.3 на реальному светрі), а не розкид пікселів — так її й читає
    # `_сила` («маржа рішення проти точності виміру»).
    # ЧОМУ СЮДИ НЕ ЙДЕ СКВ ВОЛОССЯ: `внутрішній_розкид_волосся` — це σ по голосах
    # волосся, тобто СПРАВЖНЯ двомодальність (балаяж, мелірування, сивина), а не
    # похибка виміру: на двох пасмах L*85/L*18 вона дає 33.6. Підставивши її в `_сила`,
    # ми знижували б силу K-CLR-02 кожній меліруваній людині «за точністю виміру»,
    # якої ніхто не мірив — і саме цю двомодальність модуль трьома рядками нижче
    # трактує як безкоштовний ДОДАТКОВИЙ крок контрасту, тобто як плюс, не як шум.
    # σ лишається під своїм іменем (його читає `bridge` як опис людини), а `розкид`
    # несе se_L рис, коли вимір його дає. На синтетиці й на hex-вводі виміру немає —
    # поле чесно None, і `_розкид` його, як і до правки, не рахує. Щоб воно ожило на
    # фотошляху, `extract.zone_stats.se_L` має доїхати в рису через
    # `лабораторія/зони_з_масок.features_from_zones` (там уже їде `внутрішній_контраст`)
    # — це окрема
    # правка в окремому модулі, не в межах цього наряду.
    _se_рис = [f.get("se_L") for f in [шк] + hair if isinstance(f, dict) and f.get("se_L")]
    розкид_особи = max(_se_рис) if _se_рис else None
    # ПЕРВИННЕ: value-контраст із ансамблю регіонів (та сама пара волосся↔шкіра). ЗАПАСНЕ: прямо.
    gap = None; _збій = None
    try:
        анс = (регіони(F, source) or {}).get("ансамбль")
        if анс and (анс.get("сирі") or {}).get("value") is not None:
            gap = анс["сирі"]["value"]
    except (AttributeError, IndexError, KeyError, TypeError, ValueError) as e:
        # Раніше тут стояв голий except, і будь-яке падіння регіонів (напр. h=None на
        # сивому волоссі) звітувалось як «регіони недоступні» — цілий шар мовчки вмирав.
        # Ловляться лише п'ять типів (не `Exception`), якими падає
        # арифметика над рисою без числа (саме той випадок h=None). Сигнал споживачу
        # тут був і лишається — `джерело` нижче несе «регіони ВПАЛИ (%s)» разом із
        # типом і текстом, тобто це не мовчання. Що в список не входить — летить у
        # `bridge.виклик` → `помилка` + `код` → рядок жінці.
        gap, _збій = None, "%s: %s" % (type(e).__name__, e)
    else:
        _збій = None
    джерело = ("регіони" if gap is not None else
               ("регіони ВПАЛИ (%s) — запасний розрахунок" % _збій if _збій
                else "запасний (регіони не дали value)"))
    if gap is None:
        gap = abs(Lh - шк["L"])
    # НЕ ЛИШЕ ВОЛОССЯ↔ШКІРА (аудит/ПРОДУКТ.md п.18). РІВЕНЬ контрасту на шкірі, темнішій
    # за опору порогів, — від більшого з ΔL* волосся↔шкіра і L*-еквівалента відносного контрасту
    # рис (`face_contrast.контраст_рис`: волосся й очі у формі Russell). `value_gap` лишається
    # фізичною ΔL* біля її шкіри: стрибки біля обличчя (суд K-CLR-02, вікна, ранг основ) міряються
    # у тих самих одиницях. Еквівалент туди не йде: чорний верх на глибокій шкірі з чорним волоссям
    # повторює її власний стрибок (Flusser), а в одиницях еквівалента він вийшов би «нижче».
    # Світліша за опору шкіра — як була.
    рис = _KC.контраст_рис(F)
    gap_рівня = max(gap, (рис or {}).get("екв_L") or 0.0)
    if gap_рівня > gap:
        джерело = "%s; рівень — відносний контраст рис (екв. %.1f L* на шкірі L*%.0f)" % (
            джерело, gap_рівня, рис["опора_L"])
    # ПРІОР СТИСНУТОГО КОНТРАСТУ (Candille 2012, PLoS ONE, європ. жінки вкл. Польщу,
    # r≈0.42 волосся↔шкіра). Пігментація волосся й шкіри позитивно корелює, тож
    # дисперсія їхньої РІЗНИЦІ падає до ~58% від того, що дала б незалежність осей
    # (відтворено: 2-2·0.42=1.16). Практично: висококонтрастний архетип (темне
    # волосся + дуже світла шкіра, «зима») ОБ'ЄКТИВНО рідший, ніж припускає рівномірний
    # поділ порогами <20/<40 — більшість людей лежить уздовж діагоналі світле-світле…
    # темне-темне. Тому «високий контраст» треба ставити проти стиснутого розподілу,
    # інакше частка «висококонтрастних» завищується. Пороги ЗСУНУТО вгору відповідно;
    # це не вимір L*-порога (його нема), а корекція на виміряну структуру осі. T2 за
    # напрямом (кореляція інваріантна до монотонного перетворення метрики M->L*),
    # самі числа порогів лишаються T3.
    рівень = рівень_контрасту(gap_рівня)    # ЄДИНЕ місце порогів (РІВНІ_КОНТРАСТУ)
    out = dict(доступно=True, L_шкіри=шк["L"], L_волосся=round(Lh,1),
               value_gap=round(gap,1), рівень=рівень, джерело_контрасту=джерело,
               gap_рівня=round(gap_рівня, 1), контраст_рис=рис,
               смуга_шкіри=шк.get("depth_band"),
               внутрішній_розкид_волосся=розкид_волосся,
               розкид=розкид_особи,          # похибка оцінки L* волосся, шкала se_L речей
               # R-PC-10: гейт осі контрасту з РЕГІОНАЛЬНИМ шумом профілю (se_L); на hex — стеля як була
               надійність_контрасту=cs.надійність_контрасту(source, розкид_особи),
               пороги="межі %.0f/%.0f L* (outfit.РІВНІ_КОНТРАСТУ — єдине джерело): напрям (зсув угору) — T2 з Candille 2012 "
                      "(стиснутий контраст, r≈0.42 волосся↔шкіра); самі числа — T3" % РІВНІ_КОНТРАСТУ,
               пріор="висококонтрастний тип рідший за рівномірне припущення — "
                     "більшість людей на діагоналі світле-світле…темне-темне")
    # ── МАКІЯЖ І СВІТЛОТА ЗОНИ ОБЛИЧЧЯ ЇДУТЬ У ОСОБІ ──────────
    # `value_gap` лишається ВЛАСНИМ контрастом людини (його читають розвилка
    # схем і бриф). Важіль K-CLR-03 не вшивається сюди, а рахується там, де
    # потрібен ліміт біля обличчя, — однією функцією `face_contrast.дозволений_контраст(особа)`,
    # якій для цього досить двох полів нижче. Ранг основ, вікно біля обличчя й суд K-CLR-02 беруть ліміт з ОДНОГО місця:
    # інакше ранг пускав би основу на крок далі, а суд ставив би «перевищує».
    out["макіяж"] = F.get("_макіяж")           # слід `colorspace.додати_макіяж`; None — не сказано/нюд
    out["L_обличчя"] = _KC.value_обличчя(F)     # K-CLR-04: слід; ліміт — від `L_шкіри`
    if розкид_волосся > C["step_min"]:
        out["примітка"] = ("волосся саме несе контраст (мелірування/балаяж) — "
                           "образ отримує додатковий крок безкоштовно")
    if R["chroma"] >= MIN_TO_EMIT:
        очі = F.get("очі")
        out["colour_contrast"] = round(max([h.get("rel_C",0) for h in hair] +
                                           ([очі.get("rel_C",0)] if очі else [])), 2)
    else:
        out["colour_contrast"] = None
        out["утримано"] = (f"colour contrast і підтон не стверджуються: надійність хроми "
                           f"{R['chroma']} < {MIN_TO_EMIT} для джерела «{source}» (K-PC-05). "
                           "Працюємо у value-термінах; про метали й білі — питати людину")
    return out
