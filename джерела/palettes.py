def _її_річ_несе(речі, за_ід, просить):
    """(назва, чи з фото) її закріпленої речі, що несе одну з сімей `просить`, або None.

    Сім'я речі — за тоном виміру (`колір_образу.FAMILIES`, навіть коли хрома низька: річ
    ЇЇ, і тінт тут важить) або за словом стилістки (`verify.сім_я_слова`) — спір виміру
    й слова вже названо у вердикті речі, тут він не вирішується вдруге."""
    import колір_образу as _КО, verify as _V
    if not просить:
        return None
    for r in (речі or []):
        повна = (за_ід or {}).get(r.get("id")) or r
        if not (повна.get("власна") and str(r.get("id") or "").startswith("її-")):
            continue
        сім = set()
        if повна.get("lab"):
            h = cs.lch(tuple(повна["lab"]))[2]
            for lo, hi, ім in _КО.FAMILIES:
                if (lo <= h < hi) if lo < hi else (h >= lo or h < hi):
                    сім.add(ім)
        for сл in (повна.get("колір_стилістки"), повна.get("колір")):
            с = _V.сім_я_слова(сл) if сл else None
            if с:
                сім |= {ім for ім in просить if ім == с or ім.split("/")[0] == с}
        if сім & set(просить):
            return повна.get("назва") or "твоя річ", bool(повна.get("фото_ід"))
    return None


