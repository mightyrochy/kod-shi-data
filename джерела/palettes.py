def _слот_словом(с):
    """Ім'я слота словом для жінки: підкреслення — пробіл, решта як у корпусі."""
    return str(с).replace("_", " ")


def _перелік(слова):
    """«а, б або в» — перелік людською, без коми перед останнім."""
    сп = [x for x in (слова or []) if x]
    if not сп:
        return ""
    return сп[0] if len(сп) == 1 else "%s або %s" % (", ".join(сп[:-1]), сп[-1])


def _сімей_дуги(дуга):
    """Сім'ї кольору, які лежать у дузі тону (`колір_образу.FAMILIES`), у порядку дуги.

    Дуга читається з обходом через 0°, як і скрізь у доборі: `lo > hi` означає, що
    вона перетинає нуль. Друга таблиця сімей тут не заводиться — береться та сама,
    якою судить решта системи."""
    import колір_образу as _КО
    if not дуга or дуга[0] is None or дуга[1] is None:
        return []
    lo, hi = float(дуга[0]), float(дуга[1])
    вих = []
    for f_lo, f_hi, ім in _КО.FAMILIES:
        перетин = (max(lo, f_lo) <= min(hi, f_hi)) if (lo <= hi and f_lo < f_hi) else None
        if перетин is None:
            # хоч одна з дуг перетинає 0° — перевіряємо через належність кінців
            у = lambda h, a, b: (a <= h <= b) if a <= b else (h >= a or h <= b)
            перетин = (у(f_lo, lo, hi) or у(f_hi, lo, hi) or у(lo, f_lo, f_hi) or у(hi, f_lo, f_hi))
        if перетин and ім not in вих:
            вих.append(ім)
    return вих


def рядок_схеми_жінці(речі, спец_слоти, за_ід=None, акцент=None, підміна=None, обрана=True,
                      великі=None, основа=None, тіло=None):
    """Один рядок ЖІНЦІ про обрану схему — або None, коли казати нема чого.

    Схема великих поверхонь (рядок 133) не обіцяє кольору на сумці чи взутті: її рядок
    будує `palette.рядок_великих` із `великі` (`пак["_схема_великі"]`), словом
    `основа` і площами на `тіло`.

    Мовчить, коли: схема кольору не просить (акцентних слотів нема); колір в образі
    є (обіцянку виконано); кольору жодної речі не виміряно (невимір — не провал, та
    сама політика, що в `обіцянка_схеми`).

    `акцент` — `bridge._пакет_каталогу` → `пак["_схема_акцент"]`: скільки кольору
    схема МАЄ в акцентних слотах пулу і в каталозі. Без нього рядок лишається
    правдивим, але коротшим: він не може відрізнити «в доборі було, образ не взяв»
    від «такого кольору сьогодні нема».
    `підміна` — `міст_основи._пакет_гілки`: названу схему донести не вдалось. Це
    інший стан, і він каже інше: не «кольору нема», а «цієї схеми код не знає».
    `обрана` — чи схему назвала САМА жінка (`пак["гілка_за_замовчуванням"]` навпаки).
    Приписати їй схему, якої вона не обирала, — рівно та помилка атрибуції, від якої
    застерігає `pipeline.акцент_образу`, тож зачин рядка тут інший.
    """
    if підміна:
        _пр = str(підміна.get("просили") or "").replace("_", " ")
        _дс = str(підміна.get("дісталось") or "").replace("_", " ")
        return ("Схеми «%s» у наборі коду сьогодні нема, тож образ зібрано за схемою «%s». "
                "Це не відмова твоєму вибору — просто цієї схеми тут ще не існує."
                % (_пр, _дс or "першою з твоїх"))
    if not спец_слоти or not isinstance(спец_слоти, dict):
        return None
    if спец_слоти.get("_поверхні") == "великі":
        import palette as _P_вел
        return _P_вел.рядок_великих(речі, спец_слоти, за_ід, великі=великі, обрана=обрана,
                                    основа=основа, тіло=тіло)
    акцентні = [с for с, сп in спец_слоти.items()
                if not str(с).startswith("_") and isinstance(сп, dict)
                and сп.get("роль") == "акцент" and сп.get("C") and float(сп["C"][0]) > 0]
    if not акцентні:
        return None
    схема = str(спец_слоти.get("_схема") or "").replace("_", " ") or None
    if not схема:
        return None
    виміряні = 0
    for r in (речі or []):
        повна = (за_ід or {}).get(r.get("id")) or r
        lab = повна.get("lab")
        if not lab and повна.get("hex"):
            try:
                lab = cs.hx(повна["hex"])
            except ValueError:
                lab = None
        if not lab:
            continue
        виміряні += 1
        if _хроматична(lab):
            return None            # обіцянку виконано — рядка нема
    if not виміряні:
        return None
    а = акцент if isinstance(акцент, dict) else {}
    у_пулі = int(а.get("кольорових") or 0)
    несуть = list((а.get("несуть") or {}).keys())
    _пор = lambda с: (_ПОРЯДОК_АКЦЕНТНИХ.index(с) if с in _ПОРЯДОК_АКЦЕНТНИХ else 99, с)
    зачин = ("Схема «%s»" % схема) if обрана else ("Схема «%s», яку взяв код," % схема)
    у_образі = {str(r.get("слот")) for r in (речі or []) if r.get("слот")}
    if у_пулі:
        де = sorted(несуть, key=_пор)
        # ДІЯ НАЗИВАЄТЬСЯ ЛИШЕ ТАМ, ДЕ ВОНА ІСНУЄ. «Не ця» — дотик по РЕЧІ ЦІЄЇ
        # картки; якщо колір у доборі лежить у слоті, якого в цьому образі нема
        # (пояс, шарф), то тицяти нема по чому, і обіцяти дотик означало б послати
        # жінку до кнопки, якої вона не знайде. Тоді кажеться, де колір є, — без дії.
        тут = [с for с in де if с in у_образі]
        if not тут:
            return ("%s тримається на кольорі, а цей образ вийшов увесь нейтральний. "
                    "Кольорові речі під неї в доборі є — у тому, чого в цьому образі нема: %s."
                    % (зачин, _перелік([_слот_словом(с) for с in де[:3]])))
        return ("%s тримається на кольорі: його мали нести %s — а цей образ вийшов "
                "увесь нейтральний. Кольорові речі під цю схему в доборі є: познач «не ця» "
                "на %s, і образ зберуть заново, з кольором."
                % (зачин, _перелік([_слот_словом(с) for с in тут[:3]]),
                   _СЛОТ_НА.get(тут[0], _слот_словом(тут[0]))))
    просить = []
    for с in sorted(акцентні, key=_пор):
        for ім in _сімей_дуги((а.get("дуги") or {}).get(с)):
            if ім not in просить:
                просить.append(ім)
    чого = _перелік([СІМЯ_СЛОВОМ.get(ім, ім) for ім in просить[:2]]) or "кольору"
    на_чому = _на_чому(речі, за_ід)
    у_каталозі = а.get("у_каталозі")
    # ДВА РІЗНІ СТАНИ — ДВА РІЗНІ РЕЧЕННЯ. «Вікна звузили» і «в каталозі цього нема»
    # означають для жінки різне: перше можна розхитати іншим випадком, друге — ні.
    хвіст = ("у каталозі такого кольору для цих речей сьогодні нема зовсім"
             if у_каталозі == 0 else
             "під твої мірки й цю нагоду такого кольору сьогодні не знайшлося")
    return ("%s просила %s — %s. Зібрано з того, що знайшлося: %s. Це брак асортименту, "
            "а не порада проти твого вибору." % (зачин, чого, хвіст, на_чому))


def _на_чому(речі, за_ід=None):
    """На чому образ стоїть насправді — словами крамниці, а не сім'ями коду.

    Назва кольору з каталогу («коричневий», «молочний») — те саме слово, яким річ
    підписана на картці, тож жінка звіряє рядок із тим, що бачить. Коли крамниця
    кольору не назвала, лишається сім'я нейтралі з `СІМЯ_СЛОВОМ`.

    ОДНЕ СЛОВО ЛЕКСИКОНУ — ОДИН РАЗ (23.09.2026, доповнення до рядка 137). Після
    #221 `колір_назва` — форма крамниці («Коричневий», «коричнева», «чорні»), і
    перелік казав «беж, коричневий, коричнева» — дві форми одного слова як два
    кольори. Слова групуються за словом лексикону з модифікатором світлоти
    (`V.слово_крамниці`: «коричнева» і «коричневий» — одне, «темно-сірий» і
    «сірий» — різні); показується перша форма крамниці. Слово поза лексиконом
    групується саме з собою."""
    import колір_образу as _КО
    назви, роди, ключі = [], [], set()
    for r in (речі or []):
        повна = (за_ід or {}).get(r.get("id")) or r
        н = str(повна.get("колір_назва") or повна.get("колір") or "").strip().lower()
        с = V.слово_крамниці(н) if н else None
        ключ = (с["ім"], с["мод"]) if с else н
        if н and ключ not in ключі:
            ключі.add(ключ)
            назви.append(н)
        lab = повна.get("lab")
        if not lab and повна.get("hex"):
            try:
                lab = cs.hx(повна["hex"])
            except ValueError:
                lab = None
        if lab:
            ім = _КО.сім_я(lab)
            if ім not in роди:
                роди.append(ім)
    # НАЗИВНИЙ ВІДМІНОК І КОМА, А НЕ «або»: слова крамниці («хакі», «кемел») код
    # відмінювати не вміє й не має чим, тож речення побудоване так, щоб цього й не
    # треба було — «зібрано з того, що знайшлося: персиковий, хакі, темно-сірий».
    if назви:
        return ", ".join(назви[:3])
    return ", ".join(СІМЯ_СЛОВОМ.get(ім, ім) for ім in роди[:2]) or "нейтралі"


# ── ЩО З ПАЛІТРИ ЇДЕ ДО МОДЕЛІ Й У ОПИС ──────────────────────────────────────
# ЧОМУ ОКРЕМА ФУНКЦІЯ, А НЕ ШМАТОК `людина_для_пакета`. Те саме треба двом
# викликам — пакету (руки 1–2) і опису (рука 4), — і два склади того самого
# розійшлись би на першій правці одного з них: жінці сказали б про метал в описі
# і не сказали б у пакеті, або навпаки. Тут один склад.
# ЧИСЕЛ НЕМА НАВМИСНО. Промпт від початку забороняє моделі говорити нашою шкалою
# («не називай чисел світлоти»), а `словами` вже має для кожної осі СЛОВО. Тому
# сюди їдуть слова прийомів і назви кольорів із hex — те, чим модель однаково
# говорить із жінкою, — і жодного L*, C* чи позиції осі.
def для_пакета(П, поєднань=3):
    """Метал, найдальші кольори, кілька поєднань і активні прийоми — словами.

    K-PAL-11 (метал), K-PAL-14 (найдальші), K-PAL-15 (поєднання), K-PAL-02…13
    (прийоми, доступні саме цьому типові контрасту). Усі чотири доти рахувались і
    не доїжджали: пакет знав про палітру лише схему, ролі слотів, нейтралі й
    акценти, а `словами` (де все це є) ішло тільки в бриф для людини.
    """
    if not П:
        return {}
    вих = {}
    м = П.get("метал")
    if м:
        вих["метал"] = метал_словами(м)
    д = (П.get("найдальші") or {}).get("словами")
    if д and "нема вираженої осі" not in д:
        вих["найдальші"] = д
    трійки = []
    for п in (П.get("поєднання") or [])[:поєднань]:
        трійки.append(dict(прийом=str(п.get("прийом") or ""),
                           кольори=[" ".join(x for x in (к.get("назва"), к.get("hex")) if x)
                                    for к in (п.get("кольори") or [])]))
    if трійки:
        вих["поєднання"] = трійки
    акт = []
    for x in (П.get("прийоми") or []):
        if not x.get("активний"):
            continue
        п = ПРИЙОМИ.get(x["прийом"]) or {}
        т = str(п.get("суть_моделі") or x.get("суть") or "")
        # ГЕЙТ, А НЕ ВІРА: ID корпусу в тексті для моделі — витік (гейт §41), і
        # `_без_ід` знімає його, ламаючи речення. Прийом, чия суть посилається на
        # чуже правило, мусить нести `суть_моделі`; мовчазного пропуску тут нема.
        assert not _re_pal.search(т), ("прийом «%s»: суть для моделі несе ID корпусу" % x["прийом"])
        акт.append(dict(прийом=str(x["прийом"]), суть=т))
    if акт:
        вих["прийоми"] = акт
    return вих


def словами(П):
    """Палітра словами для жінки й брифа руки: осі й домінанта, вікно й метал, сім'ї, нейтралі,
    доступні прийоми, найдальші, до чотирьох поєднань, сезон гардеробу і статус."""
    ос = П["осі"]; p = ос["позиція"]
    дом = ос["домінанта"]; вт = ос["вторинна"]
    ч = []
    ч.append("Ваші осі: світлота — %s (%.2f), ясність — %s (%.2f), температура — %s (%.2f; %s)." %
             (ос["словами"]["value"], p["value"], ос["словами"]["chroma"], p["chroma"], ос["словами"]["hue"], p["hue"], ос["джерело_hue"]))
    ч.append("Домінанта: %s%s." % (ос["словами"][дом] if дом else "нема вираженої — палітра широка, тримається мікроклімату рис",
                                  (", вторинна — " + ос["словами"][вт]) if вт else ""))
    L = П["вікна"]["L"]; C = П["вікна"]["C"]
    ч.append("Вікно палітри: світлота %.0f–%.0f, хрома %.0f–%.0f; метал — %s." % (L[0], L[1], C[0], C[1], П["метал"]))
