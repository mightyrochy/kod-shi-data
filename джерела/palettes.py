# ── ТОНАЛЬНА — ОДИН ТОН НА РЕЧАХ, А НЕ «ХОЧ ЩОСЬ КОЛЬОРОВЕ» ─────────
# Екран обіцяє «один тон на всіх речах із маленькими кроками за світлотою», а «схема вийшла»
# рахувалась так само, як для «нейтрали+акцент»: будь-яка кольорова річ. Розбір: з 15 «так»
# тональної 12 — одна сумка, клатч чи хустка (`#39873a`, `#7abadd`). Тепер тональна вийшла, коли
# тон схеми несе хоч одна ВЕЛИКА річ. Тон — дуга слота зі спеки, предикат пулу
# (`колір_річ.несе_тон`: вимір і слово — вікном з силою); тональна приглушена
# (C* 14–34 лежить і в теплому коридорі нейтралі), тож виміряна річ понад ахромат у дузі — теж тон.
ВЕЛИКІ_ТОНАЛЬНОЇ = ("верх", "низ", "сукня", "комплект", "верхній_шар")


def тон_тональної(речі, спец_слоти, за_ід=None):
    """{великих_виміряно, великих_на_тоні, на_тоні, поза_тоном, не_виміряно: [слоти]} або None — схема не тональна.

    «Виміряно» — у речі є колір (вимір чи вікно слова), і це не прикраса, чий колір знає лише
    слово металу. Заява несе не лише `на_тоні`, а й `поза_тоном` (виміряні речі поза дугою) та `не_виміряно`
    (колір невідомий): інакше мовна модель писала б «тільки взуття та сумка мають потрібний відтінок» над образом,
    де пояс без виміру й костюм поза дугою тону, — «тільки» про речі, яких код не міряв."""
    if not isinstance(спец_слоти, dict) or спец_слоти.get("_схема") != "тональна":
        return None
    вел_вим, вел_тон, на_тоні, поза_тоном, не_виміряно = 0, 0, [], [], []
    предмети = {к: [] for к in ("на_тоні", "поза_тоном", "не_виміряно")}
    for r in (речі or []):
        повна = (за_ід or {}).get(r.get("id")) or r
        сл = r.get("слот") or повна.get("слот")
        сп = спец_слоти.get(сл) if isinstance(спец_слоти.get(сл), dict) else {}
        предмет = dict(item_id=r.get("id"), slot=_ВМ.код_або_невідомо("slot", сл),
                       name=_ВМ.вільний(НР.на_картці(повна) or ""))
        lab = lab_повної(повна)
        if not є_колір(повна) or колір_невідомий(повна):
            не_виміряно.append(сл)
            предмети["не_виміряно"].append(предмет)
            continue
        вел = сл in ВЕЛИКІ_ТОНАЛЬНОЇ
        вел_вим += вел
        д = сп.get("дуга_тону")
        тон = bool(д) and _КР.несе_тон(повна if lab is None else dict(повна, lab=lab), д) is not None
        if д and not тон and lab is not None and not метал_речі(lab, сл, повна.get("тип")):
            тон = cs.lch(lab)[1] >= cs.ACHROMATIC_C and _КР.у_дугах_кола(dict(lab=tuple(lab)), [д]) == "так"
        if тон:
            вел_тон += вел
            на_тоні.append(сл)
            предмети["на_тоні"].append(предмет)
        else:
            поза_тоном.append(сл)
            предмети["поза_тоном"].append(предмет)
    return dict(великих_виміряно=вел_вим, великих_на_тоні=вел_тон, на_тоні=на_тоні, поза_тоном=поза_тоном,
                не_виміряно=не_виміряно, предмети=предмети)


