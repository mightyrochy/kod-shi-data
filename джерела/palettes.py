# ── K-PAL-15: ПОЄДНАННЯ ВСЕРЕДИНІ ПАЛІТРИ — «ось ці ваші кольори разом» ────────
# Стиліст видає не лише палітру, а й готові трійки. Тут трійки породжуються
# прийомами над КОЛЬОРАМИ ПАЛІТРИ з перевіркою кроку світлоти (K-COL-01) і
# бюджету хроми (K-COL-02: не більше одного гучного). Джерела — самі прийоми.
def поєднання(П, контраст_рівень=None, макс=8):
    к = П["кольори"]; крок = O.C["step_min"]; гучно = O.C["hi_C"]
    нейтр = [c for c in к if c["роль"] != "колір"]
    кол = [c for c in к if c["роль"] == "колір"]
    очі = [c for c in кол if c["сім_я"] == "очі"]
    def ок(t):
        Ls = sorted(x["L"] for x in t)
        if any(Ls[i+1]-Ls[i] < крок for i in range(len(Ls)-1)): return False
        if sum(1 for x in t if x["C"] >= гучно) > 1: return False
        if контраст_рівень == "низький" and Ls[-1]-Ls[0] > 45: return False    # K-CLR-02 напрям
        if контраст_рівень == "високий" and Ls[-1]-Ls[0] < 30: return False
        return True
    out = []
    def дод(прийом, t, чому):
        if len(t) == 3 and ок(t) and len(out) < макс:
            out.append(dict(прийом=прийом, кольори=[dict(назва=x["назва"], hex=x["hex"], роль=x["роль"], сім_я=x["сім_я"]) for x in t], чому=чому))
            # СЛІД У ТОЧЦІ СПРАЦЮВАННЯ (28.08.2026): ID правила жив лише у вільному
            # тексті «чому», і gate_reach чесно рахував ці правила як «спрацювало,
            # а слід не лишає» — лог тестувальниці не міг сказати, ЯКЕ правило дало
            # цю палітру. Запис стоїть тут, а не деінде, бо палітра будується РІВНО
            # тоді, коли прийом склався (умови ок() і трійки — вище).
            for _ід in _re_pal.findall(чому):
                _TR.запис(_ід, "палітра-прийом «%s»" % прийом, "палітри",
                          значення="; ".join(x["назва"] for x in t), сила="hint", напрям="пропонує трійку")
    темн = [c for c in нейтр if c["роль"] == "темна_нейтраль"]; світ = [c for c in нейтр if c["роль"] == "світла_нейтраль"]
    # нейтраль + акцент: її чорний + її білий + акцент від очей
    for акц in (очі or кол[:1]):
        for t in (темн[:1] + світ[:1] + [акц],): дод("нейтраль_плюс_акцент", t, "її темна й світла нейтралі + сім'я очей (K-PAL-06, R-COL-17)")
    # тон у тон: одна сім'я, три світлоти
    за_сім = {}
    for c in кол: за_сім.setdefault(c["сім_я"], []).append(c)
    for s, xs in за_сім.items():
        xs = sorted(xs, key=lambda x: x["L"])
        if len(xs) >= 3: дод("тон_у_тон", [xs[0], xs[len(xs)//2], xs[-1]], "сім'я «%s» трьома кроками світлоти (K-PAL-03, K-COL-01)" % s)
    # аналогова: сусідні сім'ї + нейтраль
    порядок = ["червона", "помаранчева", "жовта", "зелена", "синя", "фіолетова", "рожева"]
    for i in range(len(порядок)-1):
        a, b = за_сім.get(порядок[i]), за_сім.get(порядок[i+1])
        if a and b and темн: дод("аналогова", [a[0], b[-1], темн[0]], "сусідні сім'ї «%s» і «%s» з темною нейтраллю (K-PAL-04)" % (порядок[i], порядок[i+1]))
    # приглушена комплементарна: сім'я очей + комплемент приглушений
    if очі:
        h = очі[0]["h"]
        комп = [c for c in кол if c["h"] is not None and abs((c["h"] - (h+180)) % 360 - 180) <= 30 and c["C"] < гучно]
        if комп and світ: дод("приглушена_комплементарна", [очі[0], комп[0], світ[0]], "сім'я очей + приглушений комплемент + світла нейтраль (K-PAL-05, K-COL-02)")
    return out

# ── K-PAL-16: КОНТЕКСТ ВТЯГУЄ МЕЖОВИЙ КОЛІР (Kettlewell) ──────────────────────
# «Колір, ношений з високим контрастом, виглядає яскравішим, ніж поруч із м'якими
# приглушеними; нейтраль поруч із теплими читається як тепла, поруч із холодними —
# як холодна». Це R-CHEV на рівні річ↔річ, сказане як прийом практика. Діє лише
# на МЕЖОВИЙ колір (низька частка вікна) і лише коли бік людини відомий. hint.
_МЕЖОВА_ЧАСТКА = 0.20      # T3: нижче — колір межовий, є що втягувати

def контекст_втягує(ос, речі):
    """речі: список dict(lab, _частка_вікна?). Повертає список знахідок (не блокують)."""
    p = ос["позиція"]["hue"]
    if abs(p) < _ДОМІНАНТА_МІН / 2: return []
    бік = 1 if p > 0 else -1
    out = []
    for i, r in enumerate(речі):
        ч = r.get("_частка_вікна")
        if ч is None or ч >= _МЕЖОВА_ЧАСТКА or not r.get("lab"): continue
        комп = [x for j, x in enumerate(речі) if j != i and x.get("lab")]
        if not комп: continue
        b_сер = sum(x["lab"][2] for x in комп) / len(комп)
        C_сер = sum(cs.lch(x["lab"])[1] for x in комп) / len(комп)
        згода = (b_сер > O.C["b_нейтралі"][0] and бік > 0) or (b_сер < O.C["b_нейтралі"][1] and бік < 0)
        м_які = C_сер < O.C["hi_C"]
        сила = round((0.5 if згода else -0.5) * (1.0 - ч / _МЕЖОВА_ЧАСТКА) * (1.0 if м_які else 0.6), 3)
        # ── ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026) ────────────────
        #   before: · контекст втягує межовий колір у палітру [0.25]
        #   after:  · «верх»: колір ледь у палітрі — його тримають теплі компаньйони:
        #             не міняти їх на холодні
        # Старий рядок виходив ДОСЛІВНО однаковий на теплій людині з теплими
        # компаньйонами і на холодній із холодними (зміряно на двох синтетичних
        # образах: обидва «втягує … [0.25]»), тобто дві протилежні ситуації давали
        # моделі один текст. Ходу в ньому не було: «контекст» не називає ні річ, ні
        # бік, ні що робити, а `речі` знахідки в `pipeline.промпт_ремонту` не
        # друкуються — до ші доїжджають лише `суть` і число. Бік людини (`бік`) і
        # слот межової речі розпаковані рівно тут, тож речення каже, ЯКА річ ледь у
        # палітрі й у який бік вести її компанію.
        хто = r.get("слот") or r.get("назва") or r.get("id") or "річ"
        свій = "теплі" if бік > 0 else "холодні"
        чужий = "холодні" if бік > 0 else "теплі"
        свій_бік = "теплий" if бік > 0 else "холодний"
        out.append(dict(правило="K-PAL-16", сила_нп=сила, блокує=False, річ=i,
                        суть=(("«%s»: колір ледь у палітрі — його тримають %s компаньйони: "
                               "не міняти їх на %s" % (хто, свій, чужий)) if сила > 0 else
                              ("«%s»: колір ледь у палітрі, компаньйони не тримають %s бік — "
                               "дати поруч %s речі або замінити саму річ" % (хто, свій_бік, свій))),
                        чому=("частка вікна %.2f; компаньйони b*=%.1f (%s бік людини), C=%.1f (%s)" %
                              (ч, b_сер, "той самий" if згода else "протилежний", C_сер, "приглушені" if м_які else "гучні")),
                        джерело="Kettlewell 'How can colours work for multiple seasonal palettes' (K-PAL-16, T3, hint)"))
    return out

# ── K-COND-05: КАЛЕНДАРНИЙ СЕЗОН ДІЛИТЬ ПАЛІТРУ (Сидорович, Київ) ─────────────
# «які відтінки з палітри краще для осінньо-зимового гардеробу, а які для
# весняно-літнього»: глибші/тепліші — осінь-зима, світліші — весна-літо. Один
# названий український практик, T3, hint. Не рухає палітру — ТЕГУЄ її кольори.
def сезон_гардеробу(П):
    L = П["вікна"]["L"]; сер = (L[0] + L[1]) / 2
    for c in П["кольори"]:
        глиб = c["L"] < сер - 8; світл = c["L"] > сер + 8
        c["сезон_гардеробу"] = ("осінь-зима" if (глиб or (c["роль"] == "колір" and c["температура"] == "тепла" and not світл))
                                else "весна-літо" if світл else "обидва")
    return П

def для_сезону(П, сезон):
    """Підмножина палітри для «осінь-зима» / «весна-літо»."""
    return [c for c in П["кольори"] if c.get("сезон_гардеробу") in (сезон, "обидва")]

# ── K-PAL-17: ГАРДЕРОБ ПРОТИ ПАЛІТРИ — огляд і аналіз прогалин (тема 7) ───────
# Те, що стиліст робить у «closet edit» (Nachmias: «deep review of my current
# wardrobe … gap analysis … exactly what pieces were missing»; Kettlewell: «get to
# know and love your personal colour palette»). Кожна річ гардероба дістає силу
# членства й роль; прогалина — роль палітри без жодної речі. hint.
def гардероб_проти_палітри(речі, П):
    """речі: список dict(назва, hex або колір_назва, слот?). Повертає огляд і прогалини."""
    Llo, Lhi = П["вікна"]["L"]; Clo, Chi = П["вікна"]["C"]
    дуги = [a for arcs in П["вікна"]["сім_ї"].values() for a in arcs]
    def в_дузі(h): return any((a[0] <= h <= a[1]) if a[0] <= a[1] else (h >= a[0] or h <= a[1]) for a in дуги)
    огляд = []
    for r in речі:
        lab = None; частка = None
        if r.get("hex"):
            lab = cs.hx(r["hex"])
        elif r.get("колір_назва"):
            ім = V.назва_кольору(str(r["колір_назва"]).lower())
            if ім:
                в = V.ЛЕКСИКОН[ім]; lab = _центр(в)
                q = dict(L_min=Llo, L_max=Lhi, C_min=Clo, C_max=Chi, h_from=None, h_to=None, нейтраль=False)
                import feed as _F
                частка = _F.частка_вікна(в, q)
        if lab is None:
            огляд.append(dict(назва=r.get("назва"), статус="колір невідомий")); continue
        L, C, h = cs.lch(lab)
        нейтр = O.нейтраль(lab) is not None
        у_L = cs.soft(L, Llo, Lhi, cs.WIDTHS["L"]); у_C = 1.0 if нейтр else cs.soft(C, Clo, Chi, cs.WIDTHS["C"])
        у_h = 1.0 if (нейтр or в_дузі(h)) else 0.35
        # для кольору-словом: точкова сила за центром вікна назви × чи вікно взагалі
        # перетинає вікно палітри (частка>0); сама частка без дуг тону завищує синє в теплої
        сила = round(у_L * у_C * у_h * (1.0 if (частка is None or частка > 0) else 0.5), 3)
        роль = ("темна_нейтраль" if (нейтр and L < 40) else "світла_нейтраль" if (нейтр and L > 65) else
                "нейтраль" if нейтр else "акцент")
        огляд.append(dict(назва=r.get("назва"), слот=r.get("слот"), hex=r.get("hex"), L=round(L, 1), C=round(C, 1),
                          роль=роль, сила=сила, у_палітрі=(сила >= 0.5),
                          порада=("тримати біля обличчя" if сила >= 0.5 else
                                  "нести далі від обличчя або на контрасті (K-PAL-08/09)")))
    ролі_є = {x["роль"] for x in огляд if x.get("у_палітрі")}
    треба = {"темна_нейтраль": "«свій чорний» — темна нейтраль людини", "світла_нейтраль": "«свій білий»",
             "акцент": "акцент — насамперед сім'я очей"}
    прогалини = [dict(роль=k, що=v) for k, v in треба.items() if k not in ролі_є]
    return dict(огляд=огляд, прогалини=прогалини, у_палітрі=sum(1 for x in огляд if x.get("у_палітрі")),
                поза=sum(1 for x in огляд if x.get("сила") is not None and not x.get("у_палітрі")),
                правило="K-PAL-17", сила="hint",
                джерело="Nachmias (wardrobe review, gap analysis); Kettlewell; membership — вікна палітри K-PAL-01")

