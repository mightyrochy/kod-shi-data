#   · зміна ОЧЕЙ і ВОЛОССЯ — сміє (це інші риси, а не та сама під іншим світлом).
# ЩО САМЕ МІРЯЄТЬСЯ: дуги сімей у версії людини. Саме вони кажуть, ЯКИЙ синій і
