# Корпус розділяє два зсуви, і різниця між ними — увесь зміст правила:
#   · ВНУТРІШНЬООСОБОВИЙ зсув ШКІРИ (засмага, сезон, світло) НЕ СМІЄ перемикати
#     діагноз: міняється поверхня, підтон лишається;
#   · зміна ОЧЕЙ і ВОЛОССЯ — сміє (це інші риси, а не та сама під іншим світлом).
# ЩО САМЕ МІРЯЄТЬСЯ: дуги сімей у версії людини. Саме вони кажуть, ЯКИЙ синій і
