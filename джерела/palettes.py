def осі(F, source="uncontrolled", самозвіт=None):
    """Позиція на трьох осях ∈ [−1, +1]: value (−світла … +глибока), chroma (−м'яка … +ясна),
    hue (−холодна … +тепла). Домінанта — вісь із найбільшим |p| понад поріг."""
    д = PP.дані(F)
    Ls = [f["L"] for f in д.values()]
    ясн = ясність_рис(F)
    p_value = _клип((_СЕРЕД_L - sum(Ls)/len(Ls)) / _ПІВ_L) if Ls else 0.0
    p_chroma = _клип((ясн - _СЕРЕД_C) / _ПІВ_C) if ясн is not None else 0.0
    R = cs.reliability(source)
    sk = F.get("шкіра") or {}
    тепло = sk.get("тепло_сила")
    надійно = R["undertone"] >= cs.MIN_TO_EMIT
    джерело_hue = "фото"
    if самозвіт and (самозвіт.get("метал") or самозвіт.get("білий")):
        # елісітація не залежить від камери: золото/теплий білий → +, срібло/холодний → −
        зн = 0
        відповідей = 0
        if самозвіт.get("метал") == "золото": зн += 1; відповідей += 1
        if самозвіт.get("метал") == "срібло": зн -= 1; відповідей += 1
        if самозвіт.get("білий") == "теплий": зн += 1; відповідей += 1
        if самозвіт.get("білий") == "холодний": зн -= 1; відповідей += 1
        # ── СЕРЕДНЄ ПО КАНАЛАХ, А НЕ СУМА (Н-V04-011) ────────────────────────
        # Клип `_клип(0.6 * зн)` на СУМІ каналів зробив би рядок нижче про стелю
        # 0.6 неправдою: два узгоджені голоси давали 0.6·(±2) → клип ±1.00,
        # тобто РІВНО максимум осі. Виміряно на стенді: домінанта переїжджала з
        # value −0.92 на hue −1.00, і дві відповіді на картках важили більше за
        # виміряну світлоту людини. Обіцянка двома рядками вище — «самозвіт дає
        # БІК, не величину»; середнє її й виконує: один узгоджений голос і два
        # дають те саме 0.6, другий голос ПІДТВЕРДЖУЄ бік, а не подвоює його.
        # Суперечливі відповіді (золото + холодний білий) дають 0.0 — бік не
        # названий, і це чесніше за половину боку з залишку суми.
        # 0.6 — стеля самозвіту (T3): він сильніший за утримане фото, але не
        # сильніший за вимір, який стоїть на власних осях value/chroma.
        p_hue = _клип(0.6 * зн / max(1, відповідей))
        джерело_hue = "самозвіт"
    elif тепло is not None and надійно and sk.get("вісь_знак_придатний") is not False:
        # ── ГІЛКА ФОТО ПІД ТИМ САМИМ ГЕЙТОМ, ЩО Й ВІКНО (Н-V04-013, крок 4) ──
        # `надійно` питає про ЯКІСТЬ ЗАХОПЛЕННЯ, а `вісь_знак_придатний` — про те,
        # чи вісь узагалі двостороння на оголошеній популяції. Це різні питання, і
        # відповідь на друге не можна не питати: на `protocolized` вихід
        # давав «тепла (1.00; фото)» — максимум осі — зі знака, який `colorspace`
        # відмовився стверджувати. Гілка `else` (утримання) нижче вже написана
        # правильно: вона й приймає цей випадок.
        p_hue = _клип(float(тепло) / 1.5)    # тепло_сила ∈ [−1.5, 1.5] (colorspace)
    else:
        p_hue = 0.0
        # без ID правила: цей рядок їде в промпт моделі (palettes.словами → бриф руки),
        # а ID корпусу в тексті для моделі — витік (ловить гейт §41);
        # правило лишається в сліді: colorspace/K-PC-05 його записує
        джерело_hue = "утримано: підтон із фото не стверджується → нейтральна"
    поз = dict(value=round(p_value, 2), chroma=round(p_chroma, 2), hue=round(p_hue, 2))
    порядок = sorted(поз.items(), key=lambda kv: -abs(kv[1]))
    домінанта = порядок[0][0] if abs(порядок[0][1]) >= ДОМІНАНТА_МІН else None
    вторинна = порядок[1][0] if домінанта and abs(порядок[1][1]) >= ДОМІНАНТА_МІН else None
    # ── СЛОВО МУСИТЬ МАТИ СЕРЕДИНУ ─────────────────────────────
    # ЗНАЙДЕНО ПРОБОЮ, І ЦЕ БУЛО ВИДНО В ПРОМПТІ МОДЕЛІ ДОСЛІВНО:
    #   «температура — ТЕПЛА (0.00; утримано: підтон із фото не стверджується
    #    → нейтральна)»
    # Тобто в одному реченні система і стверджує бік, і каже, що не стверджує.
    # Причина — двійкове `"холодна" if p < 0 else "тепла"` без випадку нуля, а
    # `p_hue` при утриманні дорівнює РІВНО 0.0 ЗА ПОБУДОВОЮ. Отже неправда
    # виходила не зрідка, а КОЖНОМУ, хто прийшов із неконтрольованого фото, —
    # тобто всім на живому шляху. Читач бере перше слово, не дужку.
    #
    # Поріг середини — той самий `_ДОМІНАНТА_МІН`, яким модуль уже вирішує, що
    # «вісь не домінує, людина серединна по ній». Заводити друге число під те
    # саме поняття не можна: розійдуться.
    def _бік(p, низ, серед, верх):
        """КОД боку осі з середнім випадком: |p| < `_ДОМІНАНТА_МІН` → `серед`, інакше бік за знаком.

        Чому так: без середини утримана вісь (p = 0.0 за побудовою) звалась «тепла»
        кожному з неконтрольованого фото; поріг той самий, що для
        домінанти, щоб не заводити друге число під одне поняття.

        Функція віддає КОДИ, не слово (аудит/ПРОДУКТ.md п.12): українське слово («тепла»,
        «не стверджується») код писав би людині (кошик В), а `показ.html` ГІЛКУВАВСЯ б на ньому
        (`слово === 'нейтральна'`) і читав би своє ж слово як умову (кошик Б). Слово на екрані —
        сталий напис показу, по одному на код. Проза брифа, що брала слова для моделі, знята —
        `коди` — єдине, чим цей вузол говорить."""
        return серед if abs(p) < ДОМІНАНТА_МІН else (низ if p < 0 else верх)
    коди = dict(value=_бік(p_value, "light", "mid_lightness", "deep"),
                chroma=_бік(p_chroma, "soft", "mid_chroma", "clear"),
                # утримання сильніше за середину: коли осі нема ЧЕРЕЗ НАДІЙНІСТЬ,
                # чесно сказати `withheld`, а не `neutral` — це різні відповіді, і
                # друга виглядає як вимір.
                hue=("withheld" if джерело_hue.startswith("утримано")
                     else _бік(p_hue, "cool", "neutral", "warm")))
    # ── ВИСОКИЙ КОНТРАСТ НОСИТЬ ОБИДВА ПОЛЮСИ СВІТЛОТИ ──
    # `p_value` — середня світлота рис; якби вона одна задавала вікно, темне волосся робило б «глибокою»
    # навіть порцелянову шкіру: ж3 (шкіра L*88, волосся L*11, контраст 75) діставала б вікно L
    # 5–74, ж8 (L*81 / L*6, контраст 72) — 5–50, і обидві — «найдальші: світлі».
    # Палітра казала б «уникай світлого біля обличчя», а суддя K-CLR-02 при її контрасті
    # світле дозволяє (стеля = власний перепад + 15): дві відповіді на одне питання.
    # Корпус про висококонтрастну людину: «repeat the degree of contrast in the
    # clothes that frame the face» (Flusser), «create contrast in your outfits» (Lamport,
    # K-CON-01). Повторити перепад можна лише маючи обидва кінці, тож за рівня «високий»
    # (той самий `palettes.контраст_особи`, що в ранзі основ і суді) вікно L — її власна
    # смуга від «її чорного» до «її білого» (`смуга_світлоти`, K-ECHO-01), а вісь
    # світлоти в «найдальші» не обертається. Позиція й код боку (`deep`) лишаються:
    # середня світлота — правдивий вимір, змінюється лише те, що з нього виводиться.
    рівень = (контраст_особи(F, source) or {}).get("рівень") if д else None
    смуга = PP.смуга_світлоти(F) if рівень == "високий" else None
    return dict(позиція=поз, домінанта=домінанта, вторинна=вторинна,
                контраст_рівень=рівень,
                обидва_полюси_L=(tuple(смуга["межі"]) if смуга else None),
                коди={k: коди[k] for k in поз},
                # `джерело_hue` КОДОМ — те саме поле без прози, і саме його читає
                # `для_пакета` (`axes.source_hue`); прозовий `джерело_hue` лишається
                # поруч, бо `показ.html` ще звіряє його префікс «утримано» (П-5).
                джерело_код=("withheld" if джерело_hue.startswith("утримано")
                             else "self_report" if джерело_hue == "самозвіт" else "photo"),
                # `словами` — та сама відповідь СЛОВОМ. Екран її не читає
                # (Ч-3), проза брифа знята (П-5); лишилась вона для гейта §137. Рішення
                # одне (`_бік`), рендерів два, таблиця слів одна — `БІК_СЛОВОМ`.
                словами={k: БІК_СЛОВОМ[коди[k]] for k in поз}, джерело_hue=джерело_hue,
                провенанс="осі — R-MUN-05 / Sci\\ART / Lamport / JPCA; масштаби T3; домінанта = найбільша |позиція|")

# ── СІМ'Ї ТОНУ З ТЕПЛОЮ Й ХОЛОДНОЮ ВЕРСІЄЮ ───────────────────────────────────
# «Кожна палітра має свої версії синього/зеленого/червоного» (Sci\ART). Дуги —
# конвенційна колірна теорія практиків (T3): тепла червона = томат/цегла/корал,
# холодна = малина/ягода; тепла синя = бірюза/петроль, холодна = кобальт/нейві.
# ⚠ ДУГИ ПЕРЕТИНАЮТЬСЯ, І ЦЕ НАВМИСНО.
# Сім'ї практиків НЕ Є РОЗБИТТЯМ кола тону: «тепла червона» і «рожева» ділять
# 20–45°, «жовта холодна» і «зелена тепла» — 100–115°, дві температурні версії
# однієї сім'ї («жовта», «фіолетова») перекриваються за побудовою. Зробити з них
# розбиття означало б вигадати межі, яких у практиці нема, — тому перекриття
# лишається, а нічия розв'язується ЯВНО, трьома правилами (див. `перекриття_сімей`):
#   ВЕРСІЯ      — дві версії ОДНІЄЇ сім'ї: обирає вісь hue людини (`_дуги_сімей`);
#                 нейтральна людина законно носить обидві.
#   СУМІЖНІСТЬ  — дуги стикаються краєм (≤1° спільного): це межа, не перекриття.
#   ПОРЯДОК     — різні сім'ї ділять смугу: клітинку бере сім'я, ОГОЛОШЕНА РАНІШЕ
#                 в `СІМ_Ї` (`_ранг_сім_ї`). Так це й працює там, де власник
#                 мусить бути один: `bridge._ґратка_основ` ключує клітинку
#                 лексиконною назвою, не сім'єю, і перший запис виграє.
# Перед нічиєю ще стоїть ФІЛЬТР СВІТЛОТИ `_L_МІН` (T3, Berlin & Kay): «рожева»
# не існує нижче L*55, «жовта» — нижче L*45. Тому 26° спільних у червоної з
# рожевою розв'язуються світлотою на всьому темному боці, і лише на світлому
# доходить черга до порядку оголошення.
# ДУГИ — НА КОЛІ ХУДОЖНИКА, БЕЗ ПРОГАЛИН (2.14-А; аудит/ПРОДУКТ.md п.18: сім'ї тону — на колі художника).
# Дуги в кутах CIELAB мали б прогалини 10–15°, 145–150°, 190–195°, 240–250°: тон там не мав сім'ї
# (`сім_я_тону` → None), і K-PAL-07 мовчки губив річ h245, моделі їхав би колір без коду. Тому `СІМ_Ї_КОЛО` —
# ті самі дуги, перенесені на коло художника (`cs.у_коло_художника`; межі округлено до градуса), а прогалини в
# 2–5° кола закрито серединою: сусідні дуги стикаються. `СІМ_Ї` — їхній образ у CIELAB (`cs.з_кола_художника`;
# відображення монотонне, дуга переходить у дугу) для читачів дуг тону речей і рядків добору; сім'ю тону судить
# коло (`сім_я_тону`), центр фішки — середина дуги кола. Версії сімей ті самі: тепла — жовтіший бік сім'ї за
# віссю b* (`cs.тепло`), холодна — синіший; виміряно, що ця вісь так упорядковує всі шість пар версій.
СІМ_Ї_КОЛО = {
 "червона":    dict(тепла=(349, 21),  холодна=(321, 349)),
 "помаранчева":dict(тепла=(21, 91),   холодна=None),
 "жовта":      dict(тепла=(91, 123),  холодна=(117, 137)),
 "зелена":     dict(тепла=(123, 171), холодна=(171, 212)),
 "синя":       dict(тепла=(212, 236), холодна=(236, 277)),
 "фіолетова":  dict(тепла=(286, 312), холодна=(273, 294)),
 "рожева":     dict(тепла=(356, 21),  холодна=(312, 334)),
}
СІМ_Ї = {ім: {т: (None if д is None else (cs.з_кола_художника(д[0]), cs.з_кола_художника(д[1])))
              for т, д in в.items()} for ім, в in СІМ_Ї_КОЛО.items()}

def середина_дуги(д):
    """Тон CIELAB середини дуги тону `д` (CIELAB) — серединою на колі художника, не кутом CIELAB."""
    к0, к1 = cs.у_коло_художника(д[0]), cs.у_коло_художника(д[1])
    return cs.з_кола_художника((к0 + ((к1 - к0) % 360) / 2) % 360)

def версія_дуги(сім, д):
    """«тепла» / «холодна» — версія сім'ї `сім`, якій належить дуга `д` (CIELAB); None — дуга не з `СІМ_Ї`."""
    return next((т for т, дд in (СІМ_Ї.get(сім) or {}).items() if дд is not None and tuple(дд) == tuple(д)), None)
_СУМІЖНІ_ГРАДУСИ = 1        # ≤ стільки спільних градусів — стик дуг, а не перекриття

def _ранг_сім_ї(ім):
    """Порядок оголошення в `СІМ_Ї` — він же порядок переваги в нічиї."""
    return list(СІМ_Ї).index(ім)

def _градуси_дуги(дуга):
    """Множина цілих градусів дуги (lo, hi) з переходом через 0°."""
    lo, hi = дуга
    return {x % 360 for x in range(int(lo), int(hi if hi > lo else hi + 360) + 1)}

def перекриття_сімей():
    """Пари дуг `СІМ_Ї`, що перетинаються, з правилом розв'язання нічиєї для кожної.

    Три правила, і кожна пара має рівно одне (див. коментар над `СІМ_Ї`):
      «версія»      — тепла й холодна версії ОДНІЄЇ сім'ї; обирає вісь hue людини;
      «суміжність»  — ≤ `_СУМІЖНІ_ГРАДУСИ` спільних градусів: дуги стикаються краєм;
      «порядок»     — різні сім'ї на спільній смузі: виграє оголошена раніше.

    Прилад, а не прикраса: гейт вимагає, щоб правило було в КОЖНОЇ пари. Нове
    перекриття, заведене мимохідь, дасть «невідоме» і зробить гейт червоним —
    саме тому, що перекриття без оголошеного правила невідрізненне від помилки.
    """
    дуги = [(ім, темп, в[темп], _градуси_дуги(в[темп]))
            for ім, в in СІМ_Ї.items() for темп in ("тепла", "холодна") if в[темп]]
    out = []
    for i in range(len(дуги)):
        for j in range(i + 1, len(дуги)):
            (ім_а, т_а, д_а, г_а), (ім_б, т_б, д_б, г_б) = дуги[i], дуги[j]
            спільних = len(г_а & г_б)
            if not спільних: continue
            правило = ("версія" if ім_а == ім_б else
                       "суміжність" if спільних <= _СУМІЖНІ_ГРАДУСИ else
                       "порядок" if _ранг_сім_ї(ім_а) != _ранг_сім_ї(ім_б) else "невідоме")
            out.append(dict(пара=((ім_а, т_а, д_а), (ім_б, т_б, д_б)), спільних_градусів=спільних,
                            правило=правило,
                            виграє=(None if правило == "версія" else
                                    min((ім_а, ім_б), key=_ранг_сім_ї) if правило == "порядок" else None)))
    return out

def сім_я_тону(h):
    """(ім'я сім'ї, версія, дуга CIELAB) для кута тону CIELAB — за дугами `СІМ_Ї_КОЛО` на колі художника. Дуги
    кола не мають прогалин, тож None — лише без кута (виклик із None падає раніше).

    ЧОМУ ОКРЕМОЮ ФУНКЦІЄЮ, А НЕ ІНЛАЙНОМ У ВИКЛИКАЧА. Дуги `СІМ_Ї`
    ПЕРЕТИНАЮТЬСЯ навмисно (див. коментар над таблицею), тож «яка це сім'я»
    без оголошеного правила нічиї — не питання з однією відповіддю. Правило
    вже оголошене там і зветься ПОРЯДОК: клітинку бере сім'я, оголошена раніше.
    Тут воно просто ВИКОНУЄТЬСЯ (ітерація йде порядком `СІМ_Ї`), а не
    переписується вдруге на боці викликача — інакше «червона» і «рожева» на
    спільних 20–45° розійшлись би між двома місцями коду.
    Фільтр світлоти `_L_МІН` сюди НЕ входить: він про те, чи існує клітинка
    основи на цій світлоті (`bridge._ґратка_основ`), а не про те, якої сім'ї
    вже обраний кут."""
    к = cs.у_коло_художника(float(h) % 360)
    for ім, в in СІМ_Ї_КОЛО.items():
        for темп in ("тепла", "холодна"):
            д = в.get(темп)
            if not д:
                continue
            lo, hi = float(д[0]), float(д[1])
            у = (lo <= к <= hi) if lo <= hi else (к >= lo or к <= hi)
            if у:
                return ім, темп, tuple(СІМ_Ї[ім][темп])
    return None


def вікно_світлоти(ос):
    """Вікно світлоти L* палітри з позиції людини на осі value: домінантна вісь звужує вікно на свій
    бік (світла → 55–95, глибока → 5–50), інакше ±35 навколо центру 50 − 20·p; за високого
    контрасту — її власна смуга «її чорний … її білий» (`осі`["обидва_полюси_L"]).

    Чому так: практикове правило «палітра поділяє домінанту людини» (K-PAL-01:
    Sci\ART/Kalisz, Lamport, JPCA). Самі межі — T3, не калібровані (масштаби осей —
    коментар над `осі`)."""
    p = ос["позиція"]["value"]; дом = ос["домінанта"] == "value"
    # високий контраст: її власна смуга «її чорний … її білий» (див. `осі`)
    if ос.get("обидва_полюси_L"):
        lo, hi = ос["обидва_полюси_L"]
        return (max(5.0, float(lo)), min(95.0, float(hi)))
    # домінанта звужує вікно на свій бік; інакше — широке з нахилом
    if дом and p < 0: return (55.0, 95.0)
    if дом and p > 0: return (5.0, 50.0)
    c = 50.0 - p * 20.0
    return (max(5.0, c - 35.0), min(95.0, c + 35.0))

def вікно_хроми(ос):
    """Вікно хроми C* палітри з позиції на осі chroma: домінанта м'яка → 8–34, ясна → 30–80, інакше
    центр 30 + 15·p з плечима −20/+25.

    Чому так: те саме правило домінанти, що й у `_вікно_L`; числа — T3."""
    p = ос["позиція"]["chroma"]; дом = ос["домінанта"] == "chroma"
    if дом and p < 0: return (8.0, 34.0)
    if дом and p > 0: return (30.0, 80.0)
    c = 30.0 + p * 15.0
    return (max(6.0, c - 20.0), min(80.0, c + 25.0))


def колір_очей(р):
    """Спільний запис кольору райдужки з L/C/h профілю; None — осі відсутні."""
    if not р or any(р.get(k) is None for k in ("L", "C", "h")):
        return None
    return _КР.запис_кольору(dict(lab=lab_з_lch(float(р["L"]), float(р["C"]), float(р["h"]))))

def дуга_очей(очі_h):
    """Геометрія запиту сім'ї очей: ±`RELATIONS["analogous"]`° кола художника.

    Належність речі до сім'ї судить `колір_річ.у_відлунні_очей` за повним
    записом райдужки (`вікна.очі`), а не лише за цією геометрією тону.
    """
    return tuple(round(x, 1) for x in cs.дуга_кола(float(очі_h) % 360, cs.RELATIONS["analogous"][1]))

def дуги_сімей(ос, очі_h=None):
    """Дуги сімей у версії людини. Сім'я ОЧЕЙ додається завжди: «ваші власні кольори — у
    вашій палітрі» (Sci\\ART-лінія; Zyla; Perrett 2023) — навіть якщо тон райдужки лежить
    на «чужому» температурному боці (сіро-зелені очі в теплої людини).

    Сім'я очей — відлуння їхнього кольору (K-PAL-02, п.18) на колі художника: та сама ширина
    `RELATIONS["analogous"]` (±30°), що рахується градусами кола (`cs.дуга_кола`);
    це геометрія запиту, а належність з усіма осями райдужки судить
    `колір_відношення.сила_відлуння_очей` (наряд 935-ОЧІ). Геометрію звірено очима на каталозі: ±15° кола (`same_hue`) розводив карі очі #4a2f1f і шоколадні черевики
    #40221f (33° кола), блакитні #7fa6c8 і волошкову сукню #2e6cc3 (26°); ±45° (`near_hue`) зі згасанням
    зводив карі очі з фуксією #d92e63 (51°), зелені #5f8a5a — з лимонними штанами #978636 (46°). Кут CIELAB
    так не годиться: ±30° CIELAB — це ±18° кола в синіх і ±53° у карих (карі h 55 «відлунювали» б гірчицею h 85).
    """
    p = ос["позиція"]["hue"]
    out = {}
    if очі_h is not None:
        out["очі"] = [дуга_очей(очі_h)]
    for ім, в in СІМ_Ї.items():
        if p > ДОМІНАНТА_МІН / 2 and в["тепла"]: out[ім] = [в["тепла"]]
        elif p < -ДОМІНАНТА_МІН / 2 and в["холодна"]: out[ім] = [в["холодна"]]
        else: out[ім] = [a for a in (в["тепла"], в["холодна"]) if a]   # нейтральна людина носить обидві версії
    return out

def lab_з_lch(L, C, h):
    """Lab із (L, C, h)."""
    r = math.radians(h); return (L, C * math.cos(r), C * math.sin(r))

def _в_дузі(h, д):
    """Тон h лежить у дузі д = (від, до) кола 0–360° (дуга може переходити через 0°)."""
    a, b = д
    return (a <= h <= b) if a <= b else (h >= a or h <= b)

def _відстань_до_дуги(h, д):
    """Кут (°) від тону h до найближчого краю дуги д, коротшим шляхом по колу."""
    return min(min((h - x) % 360, (x - h) % 360) for x in д)

def _тон_поруч(ім, h, C, дh):
    """Чи тон h із хромою C, що лежить за дугою слова `ім` на дh° CIELAB, ще «ближній» до неї: різниця тону
    ΔH* = 2·C·sin(дh/2) у вікні `near_hue` (п.18, `колір_відношення`: вікно тону ширшає зі спадом
    насиченості) і не далі `МЕЖА_БЛИЗЬКИХ` — градусів кола художника, тож і відстань до краю дуги — на колі
    (2.14-А: доти дh CIELAB порівнювався з межею кола). Бік (підтон) задає дуга ВЖИТКУ слова в крамницях
    (`V.вікно_вжитку`): тон за нею — інше слово (тон 345° — не «темно-синій», дуга якого вжитку кінчається на 312°)."""
    к = cs.у_коло_художника(h)
    д_кола = min(min((к - x) % 360, (x - к) % 360) for x in map(cs.у_коло_художника, V.ЛЕКСИКОН[ім][4]))
    return (д_кола <= _КВ.МЕЖА_БЛИЗЬКИХ and 2 * C * math.sin(math.radians(дh) / 2) <= _КВ.ВІКНА_ΔH["near_hue"][0]
            and _в_дузі(h, V.вікно_вжитку(ім)[4]))

def назва(lab, виключити=None):
    """Українська назва з лексикону: НАЙТІСНІШЕ вікно, що містить точку; інакше
    найближче за ΔE00 до центру. `виключити` — множина слів, які не годяться як
    ПІДПИС (лишаються в лексиконі, просто не беруть участь у виборі тут) —
    для клітинки ҐРАТКИ ОСНОВ (`V.МЕТАЛИ`): клітинка не річ,
    фактури нема, і слово металевого блиску на матовій основі оманливе.

    ЧОМУ НАЙТІСНІШЕ, А НЕ ПЕРШЕ. Вікна лексикону
    навмисно перетинаються: широке слово («червоний», «зелений») накриває вужчі
    («цегляний», «бірюзовий»). Доти тут вигравало перше за ПОРЯДКОМ ОГОЛОШЕННЯ —
    тобто відповідь на «як зветься цей колір» залежала від порядку рядків у
    словнику, і широке слово ховало вузьке. Саме це й бачив власник: чип #c2554f
    підписувався «червоний», хоча лежить і у вікні «цегляний».
    Правило тут НЕ нове — воно вже стоїть у `жнива_v2.слово_з_lab` («вікно, що
    ВМІЩАЄ вимір, найтісніше з таких») і судить колір речей у жнивах. Правило вибору слова з перетину ОДНЕ
    на систему, і порядок рядків у `ЛЕКСИКОН` нічого не вирішує.
    Тісноту міряємо площею вікна L×C, як і `жнива_v2`: дуга тону в неї не входить
    (у нейтралей її просто нема, і вони б завжди вигравали).

    ТОН, ЯКИЙ ВИДНО, НАЗИВАЄ ВІКНО З ДУГОЮ. Вікна без дуги («білий», «сірий»,
    «срібний», «графіт», «чорний») тримають C* до 11, і як найтісніші вони підписували й
    точку з видимим тоном: вівсяний #E6DCCD (C*8.6, тон 84°) ставав «білим», сизий #8C97A6 —
    «срібним», темно-коричневий #3C2E2A — «графітом»; код кольору мовного шару писав це
    словом на картці. Від C* `V.ДРІЖ_AB` (6 — рівень, вище якого тон не шум, Л-14)
    вікно без дуги точку не підписує, коли її вміщає вікно з дугою; нижче — без змін.
    Рівну тісноту розв'язує ближчий центр вікна (ΔE00, як і гілка «найближче»), а не
    абетка: «вершковий» і «молочний» мають одну площу 484, і світлі теплі точки йшли у
    «вершковий» лише тому, що «в» стоїть перед «м». ВИМІРЯНО (`проби/колір_hex_вікна.py`,
    разом із вікном «лимонний»): точки крамниць з виміром з фото — підпис змінився в 726
    із 9 445, збіг зі словом крамниці 3 833 → 4 051; hex з відповідей моделі — код
    змінився в 302 із 3 220; ґратка основ — побайтово та сама; записи каталогу — 6
    (центр «лимонного», блок у `verify.ЛЕКСИКОН`). Не лікується тут #D3D3D3 (C* 0, L*84.6):
    він лежить нижче білої основи ґратки #d7d7d7 (L*86), і крамниці на фото так світлі
    нейтралі звуть «білий» (L*82–86, C*<3: 26 проти 6 «сірих»).

    ТОН ПОРУЧ З ДУГОЮ. Темні теплі майже нейтралі тону 330–30° (L*15–50, C*6–12)
    лежали за дугою «коричневого» (30–95°), жодне вікно з дугою їх не вміщало, і вони йшли в
    «графіт»/«чорний» — а крамниці звуть їх «коричневий» (60 із 100), «шоколадний» (15): вжиток
    слова сягає 330°. П.18: вікно тону ширшає зі спадом насиченості — тож від C* `V.ДРІЖ_AB`, коли
    дугу точка не влучила, слово з дугою годиться, якщо різниця тону ΔH* = 2·C*·sin(Δh/2) до краю
    його дуги в `колір_відношення.ВІКНА_ΔH["near_hue"]` (9; C* 8 — до 68°, C* 12 — до 44°) і Δh не
    більше `МЕЖА_БЛИЗЬКИХ`; бік (підтон) задає дуга ВЖИТКУ слова (`V.вікно_вжитку`), інакше тон
    345° ішов би в «темно-синій» (його дуга 240–310°). Межею лишаються світлота й хрома вікна, як і
    були. Вибір серед таких — найтісніше. ВИМІРЯНО (`проби/колір_майже_нейтраль.py`):
    у смузі 100 точок крамниць «графіт» 81 / «чорний» 16 / «сірий» 3 → «шоколадний» 73 /
    «коричневий» 27; збіг зі словом крамниці в смузі 6 → 29; в усьому каталозі підпис змінився в
    231 із 9 445, збіг 4 092 → 4 135; ґратка основ — побайтово та сама."""
    L, C, h = cs.lch(lab)
    # слова з вікном із того, як крамниці називають РЕЧІ (`V.ВІКНА_КРАМНИЦЬ`),
    # точку не підписують ніколи: вони свідки поля кольору, а не
    # назви чипа — інакше нове слово тихо з'явилось би на екрані палітри
    виключити = V.ВІКНА_КРАМНИЦЬ | frozenset(виключити or ())
    вміщають, поруч = [], []
    for ім, (Llo, Lhi, Clo, Chi, д) in V.ЛЕКСИКОН.items():
        if ім in виключити: continue
        if not (Llo <= L <= Lhi and Clo <= C <= Chi): continue
        пл = (Lhi - Llo) * (Chi - Clo)
        if д is not None and not _в_дузі(h, д):
            поруч.append((пл, ім, _відстань_до_дуги(h, д)))
            continue
        вміщають.append((пл, д is None, ім))
    if C >= V.ДРІЖ_AB and not any(not без for _, без, _ in вміщають):
        ближні = [(пл, False, ім) for пл, ім, дh in поруч if _тон_поруч(ім, h, C, дh)]
        if ближні: вміщають = ближні
    if C >= V.ДРІЖ_AB and any(not без for _, без, _ in вміщають):
        вміщають = [в for в in вміщають if not в[1]]
    if вміщають: return min(вміщають, key=lambda в: (в[0], cs.de00(lab, центр(V.ЛЕКСИКОН[в[2]]))))[2], "у вікні"
    кандидати = [kv for kv in V.ЛЕКСИКОН.items() if kv[0] not in виключити]
    найбл = min(кандидати, key=lambda kv: cs.de00(lab, центр(kv[1])))
    return найбл[0], "найближче"

def центр(в):
    """Центр вікна (Llo, Lhi, Clo, Chi, дуга) як Lab; середина дуги — коротким шляхом через 0°, без
    дуги h = 0."""
    Llo, Lhi, Clo, Chi, д = в
    h = 0.0 if д is None else (д[0] + ((д[1] - д[0]) % 360) / 2) % 360
    return lab_з_lch((Llo + Lhi) / 2, (Clo + Chi) / 2, h)

def hex_з_lab(lab):
    """«#rrggbb» із Lab; канали поза гамутом sRGB обрізаються до [0, 1].

    Це показ кольору на екрані, не твердження про відтворюваність: стеля реальної
    поверхні — окреме питання (`colorspace.c_max_поверхня`, R-COL-12)."""
    r, g, b = cs.to_rgb(*lab)          # 0..1 (sRGB), може виходити за гамут — обрізаємо
    return "#%02x%02x%02x" % tuple(int(round(max(0.0, min(1.0, x)) * 255)) for x in (r, g, b))

def кольори(ос, П_рис, n_L=3, вікно_L=None, вікно_C=None, усі_версії=False):
    """Конкретні кольори палітри: сім'я × світлота × хрома всередині вікон людини,
    обрізано стелею реальної поверхні (Pointer, R-COL-12). Плюс нейтралі з рис.

    ── РОЗКРИТІ ВІКНА = УНІВЕРСАЛЬНА ҐРАТКА ──────────────────────
    `вікно_L` / `вікно_C` / `усі_версії` роблять із цієї ж функції генератор УСЬОГО
    носибельного простору, а не вікна однієї людини. Це потрібно основам: список
    баз мусить бути розбиттям простору, а не переліком того, що завіз магазин чи
    що пасує конкретній жінці. Людина обирає з усього законного; ранг каже, що з
    цього їй радять. Межі [5, 95] і [6, 80] не нові — вони вже стоять хардкапами
    у `_вікно_L` / `_вікно_C`, тут лише знімається персональне звуження.
    `усі_версії` бере і теплу, і холодну дугу кожної сім'ї: без цього ґратка
    залежала б від температури людини, тобто знову не була б універсальною."""
    Llo, Lhi = вікно_L or вікно_світлоти(ос); Clo, Chi = вікно_C or вікно_хроми(ос)
    очі_h = next((r["центр"] for r in П_рис["родини"]["родини"] if r["рід"] == "очі" and r.get("відношення") == "analogous"), None)
    дуги = ({ім: [a for a in (в["тепла"], в["холодна"]) if a] for ім, в in СІМ_Ї.items()}
            if усі_версії else дуги_сімей(ос, очі_h))
    out = []
    Ls = [Llo + (Lhi - Llo) * (i + 0.5) / n_L for i in range(n_L)]
    _L_МІН = {"рожева": 55.0, "жовта": 45.0}    # T3: рожевий — світлий червоний (Berlin & Kay), темного жовтого нема
    for сім, arcs in дуги.items():
        for a in arcs:
            h = середина_дуги(a)
            # ПІДПИС ТЕПЛА — ВЕРСІЯ СІМ'Ї (2.14-А): знак b* центру ставив би 4 з 13 фішок проти власної версії
            # (зелена-холодна h170 — «тепла», синя-тепла h217.5 — «холодна»). Фішка сім'ї очей версії не має —
            # її бік за віссю тепла (`cs.тепло`), тим самим визначенням.
            темп = версія_дуги(сім, a) or ("тепла" if cs.тепло(h) >= 0 else "холодна")
            for L in Ls:
                if L < _L_МІН.get(сім, 0.0): continue
                стеля, стеля_джерело = cs.c_max_поверхня(L, h)     # (стеля, джерело) — R-COL-12
                C = min(Chi, стеля if стеля else Chi)
                if C < Clo: continue                      # тканина цього не дає
                for Cx in sorted({round(C, 1), round(max(Clo, (Clo + C) / 2), 1)}, reverse=True):   # спадання хроми: порядок задано значенням, не хешем множини (Pyodide ≠ CPython)
                    lab = lab_з_lch(L, Cx, h)
                    ім, як = назва(lab)
                    out.append(dict(сім_я=сім, роль="колір", дуга=a, L=round(L, 1), C=Cx, h=round(h, 1),
                                    lab=tuple(round(x, 1) for x in lab), hex=hex_з_lab(lab), назва=ім, назва_як=як,
                                    температура=темп,
                                    стеля_хроми=стеля_джерело))
    # нейтралі — з рис (personal_palette) + ахроматика у смузі світлоти людини
    for н in П_рис["нейтралі"]:
        lab = lab_з_lch(н["L"], min(8.0, _РЕЄСТР.C["neutral_C"] - 1), 90 if н["сім_я"] == "тепла" else 270 if н["сім_я"] == "холодна" else 0)
        lab = (н["L"], lab[1] if н["сім_я"] != "ахроматична" else 0.0, lab[2] if н["сім_я"] != "ахроматична" else 0.0)
        ім, як = назва(lab)
