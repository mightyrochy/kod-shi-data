def палітра_практична(F, source="uncontrolled", самозвіт=None, контраст_рівень=None, intent="conventional"):
    П = _палітра_практична(F, source, самозвіт, контраст_рівень, intent)
    П["поєднання"] = поєднання(П, контраст_рівень)
    h_шк = (F.get("шкіра") or {}).get("h")
    for c in П["кольори"]:
        c["тон"] = cs.тон(c["lab"])                       # R-COL-14 / R-MUN-08
        c["знак_проксі"] = знак_проксі(c["h"], h_шк) if c["роль"] == "колір" else None
    # слід K-PCA-01 — ОДИН на палітру, з агрегатом: те саме правило на 12 кольорах —
    # одна знахідка, не 12 (семантика trace.зібрати)
    _пк = [c["знак_проксі"]["бік"] for c in П["кольори"] if c.get("знак_проксі")]
    if _пк:
        _слід("K-PCA-01", "знак-проксі напряму індукції на шкіру (T4 перенос — останній ключ сортування, не фільтр)",
              значення="до здоровішого %d / від %d" % (_пк.count("до здоровішого"), _пк.count("від здоровішого")), сила="hint")
    _слід("K-PAL-01", "палітра людини: правило породження", значення=П["осі"]["домінанта"], сила="default")
    _слід("R-COL-17", "порядок рис: очі перші", значення=1, сила="default")
    _слід("K-PAL-14", "найдальші кольори", значення=П["найдальші"]["словами"])
    _слід("K-PAL-15", "поєднання всередині палітри", значення=len(П["поєднання"]))
    _слід("K-COND-02", "засмага не рухає вікна", значення="ключ від очей", сила="default")
    сезон_гардеробу(П)                                  # K-COND-05
    return П

def _палітра_практична(F, source="uncontrolled", самозвіт=None, контраст_рівень=None, intent="conventional"):
    ос = осі(F, source, самозвіт)
    П_рис = PP.палітра(F, source=source)
    к = кольори(ос, П_рис)
    очі_h = next((r["центр"] for r in П_рис["родини"]["родини"] if r["рід"] == "очі" and r.get("відношення") == "analogous"), None)
    вік = dict(L=_вікно_L(ос), C=_вікно_C(ос), сім_ї=_дуги_сімей(ос, очі_h))
    метал = ("золото" if ос["позиція"]["hue"] > _ДОМІНАНТА_МІН / 2 else
             "срібло" if ос["позиція"]["hue"] < -_ДОМІНАНТА_МІН / 2 else "обидва")
    return dict(осі=ос, вікна=вік, кольори=к, метал=метал,
                найдальші=найдальші(ос),
                поєднання=None,   # заповнюється нижче, бо потребує кольорів
                прийоми=прийоми(ос, контраст_рівень, intent,
                                волосся_ахроматичне=any((f.get("C", 99) or 0) < cs.ACHROMATIC_C
                                                        for nm, f in PP._дані(F).items() if nm.startswith("волосся"))),
                мікроклімат=dict(нейтралі=П_рис["нейтралі"],
                                 акценти_від_очей=[r for r in П_рис["родини"]["родини"] if r["рід"] == "очі" and r.get("дуга")][:3],
                                 макіяж=П_рис["макіяж"]),
                провенанс=dict(правило_породження="палітра поділяє домінанту людини — Sci\\ART/Kalisz 2003, Lamport, JPCA; "
                                                  "Radeloff 1990: спостерігачі згодні з практиками · default як практикове рішення",
                               числа="масштаби осей, вікна, дуги сімей — T3 · hint",
                               мікроклімат="TCI «microclimate»; Zyla; Perrett 2023 (очі)"),
                статус=("це відповідь ПРАКТИКІВ на «які кольори належать мені», породжена їхнім правилом; "
                        "що вона «личить» — не виміряно; сезонного ярлика не видається (R-PC-01)"))

def рядки_у_фід(спец):
    """Рядки каталогу з практикової палітри: сім'ї у вікнах людини (кольорові слоти) і
    нейтралі за температурою (усі слоти). Ранг: сім'я очей 1, решта сімей 2, нейтралі 2."""
    П = спец.get("палітра_практична")
    if not П: return []
    Llo, Lhi = П["вікна"]["L"]; Clo, Chi = П["вікна"]["C"]
    очі_h = [r["центр"] for r in П["мікроклімат"]["акценти_від_очей"] if r.get("відношення") == "analogous"]
    рядки = []
    for s, v in спец["слоти"].items():
        if v.get("попередження"): continue
        sLlo, sLhi = max(v["L"][0], Llo), min(v["L"][1], Lhi)
        if sLlo > sLhi: continue
        # нейтралі за температурою палітри
        r = dict(слот=s, L_min=sLlo, L_max=sLhi, C_min=0.0, C_max=max(O.C["warm_neutral"][2], O.C["cool_neutral"][2]),
                 h_from=None, h_to=None, нейтраль=True, роль="нейтраль_палітри", ранг_риси=2,
                 джерело_тону="палітра_практична:нейтраль", чому="нейтраль у смузі світлоти палітри; температура — бік людини")
        if П["метал"] == "золото": r["b_min"] = O.C["b_нейтралі"][0]
        elif П["метал"] == "срібло": r["b_max"] = O.C["b_нейтралі"][1]
        рядки.append(r)
        if "сім_я" in v: continue
        for сім, arcs in П["вікна"]["сім_ї"].items():
            for a in arcs:
                c = (a[0] + ((a[1] - a[0]) % 360) / 2) % 360
                очі = (сім == "очі") or any(abs((c - h + 180) % 360 - 180) <= 30 for h in очі_h)
                рядки.append(dict(слот=s, L_min=sLlo, L_max=sLhi, C_min=max(v["C"][0], Clo), C_max=min(v["C"][1], Chi),
                                  h_from=a[0], h_to=a[1], нейтраль=False, роль="сім_я_палітри:%s" % сім,
                                  ранг_риси=(1 if очі else 2), джерело_тону="палітра_практична:%s" % сім,
                                  чому=("сім'я «%s» у версії %s людини; %s" %
                                        (сім, "теплій" if 0 <= c < 180 else "холодній",
                                         "збігається з сім'єю очей — ранг 1" if очі else "ранг 2"))))
    рядки = [q for q in рядки if q["C_min"] <= q["C_max"]]
    рядки.sort(key=lambda q: q["ранг_риси"])
    return рядки

def словами(П):
    ос = П["осі"]; p = ос["позиція"]
    дом = ос["домінанта"]; вт = ос["вторинна"]
    ч = []
    ч.append("Ваші осі: світлота — %s (%.2f), ясність — %s (%.2f), температура — %s (%.2f; %s)." %
             (ос["словами"]["value"], p["value"], ос["словами"]["chroma"], p["chroma"], ос["словами"]["hue"], p["hue"], ос["джерело_hue"]))
    ч.append("Домінанта: %s%s." % (ос["словами"][дом] if дом else "нема вираженої — палітра широка, тримається мікроклімату рис",
                                  (", вторинна — " + ос["словами"][вт]) if вт else ""))
    L = П["вікна"]["L"]; C = П["вікна"]["C"]
    ч.append("Вікно палітри: світлота %.0f–%.0f, хрома %.0f–%.0f; метал — %s." % (L[0], L[1], C[0], C[1], П["метал"]))
    сім = {}
    for c in П["кольори"]:
        if c["роль"] == "колір": сім.setdefault(c["сім_я"], []).append(c["назва"])
    ч.append("Сім'ї у вашій версії: " + "; ".join("%s — %s" % (s, ", ".join(dict.fromkeys(n))) for s, n in сім.items()) + ".")
    н = [c for c in П["кольори"] if c["роль"] != "колір"]
    if н: ч.append("Ваші нейтралі: " + ", ".join(dict.fromkeys("%s (%s, L*%.0f)" % (c["назва"], c["температура"], c["L"]) for c in н)) + ".")
    акт = [x["прийом"] for x in П["прийоми"] if x["активний"]]
    ч.append("Прийоми, доступні зараз: " + ", ".join(акт) + ".")
    if П.get("найдальші"): ч.append("Найдальші від ваших осей (не заборона — нести далі від обличчя або на контрасті): %s." % П["найдальші"]["словами"])
