    # дедуплікація за назвою+роллю, сила = членство у смугах людини
    seen, uniq = set(), []
    for c in out:
        k = (c["назва"], c["роль"], c["сім_я"], int(c["L"] // 20))   # світла й темна версії однієї назви — різні кольори
        if k in seen: continue
        seen.add(k)
        # ОДНА СТЕЛЯ ДЛЯ ДВОХ ЧАСТОК. Смуга хроми людини — rel_C рис, нормований
        # на Cmax(sRGB) (`colorspace.describe`, `personal_palette.смуга_хроми`); кандидат
        # нормувався на Cmax поверхні (Pointer), тож «частка» кандидата й смуга мали різний
        # зміст (L40 h250: 29,9 проти 55,4). Pointer лишається там, де він про тканину, —
        # обрізати C кандидата (`кольори`, R-COL-12); членство в її смузі — тією ж шкалою, що
        # й `колір_простір_риси.feature_votes`.
        _ст = cs.c_max(c["L"], c["h"] or 0) if c["h"] is not None else None
        c["сила"] = round(PP.членство(св, c["L"]) *
                          (PP.членство(П_рис["хрома"], c["C"] / max(1.0, _ст or 1.0))
                           if c["h"] is not None else 1.0), 3)
        uniq.append(c)
    uniq.sort(key=lambda c: (0 if c["роль"] != "колір" else 1, -c["сила"]))
    return uniq

