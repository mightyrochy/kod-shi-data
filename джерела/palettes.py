def дуга(h, пів):
    """Дуга тону CIELAB навколо `h` ± `пів` градусів КОЛА ХУДОЖНИКА, як пара (від, до) тонів CIELAB по колу 0–360.

    Чому коло, а не CIELAB: пів-ширина в CIELAB давала б блакитним очам h250
    роль комплементу ±18° CIELAB сягала 19–99° кола, і на її краях відношення до очей було тріадою, а не
    комплементом. Ширина ролі — те саме відношення тону, що й зсув, тож міряється тим самим колом
    (`colorspace.дуга_кола`); так само — ехо принту й вікно обраної основи, що беруть цю дугу."""
    від, до = cs.дуга_кола(h, пів)
    return (round(від, 1), round(до, 1))

