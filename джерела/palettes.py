        """Додає трійку в `out`, якщо в ній три кольори, вона законна і стеля `макс` не вичерпана; пише
        слід за ID прийому в точці спрацювання."""
        if len(t) == 3 and ок(t) and len(out) < макс:
            out.append(dict(прийом=прийом, кольори=[dict(назва=x["назва"], hex=x["hex"], роль=x["роль"], сім_я=x["сім_я"]) for x in t], чому=чому))
            # СЛІД У ТОЧЦІ СПРАЦЮВАННЯ (28.08.2026): ID правила жив лише у вільному
            # тексті «чому», і gate_reach чесно рахував ці правила як «спрацювало,
            # а слід не лишає» — лог тестувальниці не міг сказати, ЯКЕ правило дало
            # цю палітру. Запис стоїть тут, а не деінде, бо палітра будується РІВНО
            # тоді, коли прийом склався (умови ок() і трійки — вище).
            # ID ТЕПЕР ПАРАМЕТР, А НЕ ЗНАХІДКА В ТЕКСТІ (Н-V16-038, 12.09.2026):
            # `findall(чому)` брав із «чому» ВСІ коди підряд, тож трійка нейтраль+акцент
