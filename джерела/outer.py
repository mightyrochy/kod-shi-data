# ═════════════ 12. ЄДИНИЙ ВХІД ═════════════
def перевірити(речі, тіло=None, темп_c=None, вітер=None, опади=None, реагенти=None,
               тривалість_год=None, гардероб=None):
    """Гілка верхнього шару одним викликом.

    ПОРЯДОК ЗНАЧУЩИЙ І ВЗЯТИЙ ІЗ ТЕМИ (ЧАСТИНА I): спершу K-OUT-01 вирішує, які
    правила взагалі мають голос, і лише потім вони говорять. Придушення
    застосовується В КІНЦІ, до вже зібраного списку, бо інакше кожне правило мусило б
    знати про температуру самостійно — і половина забула б.
    """
    в = _верхній(речі)
    пр = придушення(темп_c)
    if в is None:
        return dict(є_верхній_шар=False,
                    ворота=[], преференції=[], ремонти=[], команди=[],
                    питання=без_входу(речі),
                    стан=dict(є=False),
                    теплова_функція=теплова_функція(речі, темп_c),
                    придушення=пр,
                    чому="верхнього шару в образі нема — уся гілка теми-11 мовчить, "
                         "крім черги на вхід")
    усі = (теплові_знахідки(речі, темп_c)
           + довжина(речі, тіло)
           + стан_знахідки(речі, темп_c=темп_c, вітер=вітер,
                           тривалість_год=тривалість_год)
           + краї(речі, тіло)
           + драбина_припусків(речі, темп_c)
           + обʼєм_пари(речі)
           + плечова_вісь(речі, тіло)
           + фронтальний_V(речі, тіло)
           + ремонтопридатність(речі, тіло)
           + догляд(речі, реагенти=реагенти, темп_c=темп_c, опади=опади))
    _придушених = [з for з in усі if з.get("правило") in ПРИДУШУВАНІ]
    усі = _придушити(усі, пр) + придушення_знахідка(пр, _придушених)
    ремонт_зн = _придушити(ремонти(речі, темп_c=темп_c,
                                   тривалість_год=тривалість_год, гардероб=гардероб), пр)
    команди = команди_укладки(речі, темп_c=темп_c, вітер=вітер,
                              тривалість_год=тривалість_год)
    ворота = [з for з in усі if з.get("блокує")]
    питання = [з for з in усі if з.get("сила") == "питання"] + без_входу(речі)
    преференції = [з for з in усі
                   if not з.get("блокує") and з.get("сила") != "питання"]
    return dict(
        є_верхній_шар=True, річ=_імʼя(в),
        ворота=ворота, преференції=преференції, питання=питання,
        ремонти=ремонт_зн, команди=команди,
        стан=стан(речі, темп_c=темп_c, вітер=вітер, тривалість_год=тривалість_год),
        теплова_функція=теплова_функція(речі, темп_c),
        придушення=пр,
        відра="ворота ВІДКИДАЮТЬ · преференції ВПОРЯДКОВУЮТЬ · ремонти пропонують ТУ "
              "САМУ річ в іншому стані · питання — ЧЕРГА НА ВХІД. Ремонт іде ПІСЛЯ "
              "діагнозу, не замість нього",
        порядок="K-OUT-01 (яке правило має голос) → теплова функція → краї → драбина "
                "припусків → обʼєм → приобличчеві важелі → ремонтопридатність → догляд. "
                "K-OUT-01 стоїть ПЕРШИМ не за важливістю, а за типом: він не змагається "
                "з рештою правил, він вирішує, чи вони говорять")
