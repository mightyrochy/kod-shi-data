def _комір_піднято(в, темп_c, вітер):
    """K-OUT-29 — четвертий стан, і єдиний безкоштовний. K-OUT-13 — заміщення шарфа."""
    комір = в.get("комір")
    if комір in (None, "без_коміра"):
        return None
    if комір not in ("стійка", "відкладний", "ревер", "шаль"):
        return None
    рез = dict(доступно=True, комір=комір,
               чому="підняти комір на звичному тренчі чи пальті — прийом, який нічого "
                    "не коштує, не потребує іншої речі й змінює приобличчеве поле й "
                    "вертикаль (Андре Тан). Кваліфікацію особи перевірено й "
                    "підтверджено (крій, побудова викрійок), АЛЕ саме це висловлювання "
                    "лежить поза нею — воно про сезонний прийом, не про конструкцію, "
                    "тож узято МЕХАНІЗМ, не тренд, і сила обмежена жанром")
    # ── K-OUT-13: висока стійка ЗАМІЩАЄ шарф — але лише за вітрового навантаження
    if комір == "стійка" and вітер:
        рез["заміщення"] = dict(слот="шарф",
            чому="висока стійка закриває шию від вітру й дозволяє відмовитися від "
                 "шарфа: слот звільняється разом із бюджетом акценту",
            умова="діє ЛИШЕ за наявного вітрового навантаження; при +15 °C у безвітря "
                  "висока стійка не заміщає нічого — вона просто закрита горловина")
        _СЛ.запис("K-OUT-13", "стійка заміщає шарф", "стан",
                  значення="вітер=%s" % вітер, сила=None, напрям="звільнення слота")
    return рез


