def _каскад(речі, тіло):
    """K-OUT-04. Три і більше шари з монотонно зростаючими краями, кожен крок у
    смузі 2–5 см. Два шари каскаду не утворюють — нема напрямку, який можна прочитати."""
    краї_ = []
    for р in речі:
        if р.get("слот") not in ("верх", "верхній_шар", "сукня"):
            continue
        см, дж = край_см(р, тіло)
        if см is None or дж == "дефолт слота":
            return None
        краї_.append((см, _імʼя(р)))
    if len(краї_) < 3:
        return None
    краї_.sort()
    кроки = [round(краї_[i + 1][0] - краї_[i][0], 1) for i in range(len(краї_) - 1)]
    if all(C["каскад_крок_низ_см"] <= к <= C["каскад_крок_верх_см"] for к in кроки):
        return dict(речі=[n for _, n in краї_], кроки=кроки)
    return None


