# РІВЕНЬ ДОВЖИНИ → (висота від підлоги на цьому тілі, похибка см). Похибки — T3:
# ширина смуги, яку слово каталогу реально накриває («міді» — від низу коліна до
# щиколотки з гаком; «міні» — від верху стегна до колін). Не поріг: fit.краї судить
# зону край±розкид цілком, і від чисел залежить лише, наскільки широка ця зона.
_РІВЕНЬ_ЗОНА = {
 "талія":  (("талія",), 3.0),
 "стегно": (("стегна",), 5.0),
 "міні":   (("пах", "коліно"), 8.0),          # середина стегна
 "коліно": (("коліно",), 4.0),
 "литка":  (("коліно", "щиколотка"), 7.0),    # міді: середина гомілки
 "щиколотка": (("щиколотка",), 3.0),
 "максі":  (("щиколотка",), 5.0),
}

def висота_рівня(рівень, H):
    """(см від підлоги, розкид см) або (None, None), якщо рівень невідомий."""
    з = _РІВЕНЬ_ЗОНА.get(рівень)
    if not з: return None, None
    ключі, розкид = з
    вис = [H.get(k) for k in ключі]
    if any(v is None for v in вис): return None, None
    return round(sum(вис) / len(вис), 1), розкид


# ── ПОДІЛ ІЗ ДОВЖИНИ ВИРОБУ НА ЇЇ ЗРОСТІ (28.09.2026, Ф-9, звіт Research П1) ──
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. `висота_рівня` вище перекладає СЛОВО крамниці («міді») у
# сантиметри зоною ±7 см, і `fit.краї` над такою зоною виходить «питанням», щойно
# смуга накриває найширше місце лише частково, а силу вердикту зрізає до `soft`
# («T3 ≤ вимір»). Оголошена довжина виробу — вимір крамниці, і поділ рахується
# арифметикою: `рівень точки виміру на ЦЬОМУ тілі − довжина виробу`. Та сама «міді»
# 94 см від плечей лягає на 158 см на 35,6 см від підлоги (нижче литки), а на 175 см
# — на 49,5 см (на коліні): одне слово, два різні класи, і вирішує їх зріст.
# ЧОМУ ТОЧКА ВИМІРУ — ПОЛЕ, А НЕ СТАЛА: 79 см крокового шва й 79 см спідниці кладуть
# поділ у місця, що різняться на 23 см (цілий клас довжини). Точку називає крамниця
# (`фід_атрибути.довжина_виробу`), тут вона лише читається з висот тіла.
# ЧОМУ ПОДІЛ ПОЗА ТІЛОМ — НЕ ВИМІР, А БРУД: `areas._перевірити_проміжок` уже казало,
# що «пальто висотою 200 см на зрості 164» — помилка інджесту, і кидало виняток.
# Кидати його тут означало б валити живий шлях на брудному рядку каталогу, тож число
# просто не береться, а `край_джерело` лишається тим, чим був («слово» або «дефолт
# слота»), і `fit.краї` чесно виходить питанням із названим полем.
# РІЧ, ДОВША ЗА ЇЇ ТІЛО, — НЕ БРУД, А ФАКТ ПРО НЕЇ, І ЦЕ ВИМІРЯНО. На каталозі
# `каталог_повний` 168 речей зі 1 665 (10 %) дають на зрості 165 см поділ НИЖЧЕ підлоги,
# і в переважній більшості це не помилка крамниці: штани з кроковим швом 82 см на паху
# 79,2 см справді довші за її ногу, максі-сукня 142 см на плечах 135,3 см справді ляже
# на підлогу. Викидати такі речі означало б загубити рівно той висновок, по якому наряд
# і писався. Тому поділ стає на підлогу (0 см), а надлишок лишається числом —
# `довжина_надлишок_см`. Межа 30 см розділяє «довше за неї» і «число не з цієї речі»:
# розподіл надлишку на каталозі — 127 речей у смузі 0–10 см, 35 у 10–20, 6 у 20–30,
# глибше порожньо.
_НАДЛИШОК_МЕЖА_СМ = 30.0


def край_з_довжини(r, H):
    """(поділ у см від підлоги, розкид см, точка виміру, надлишок см) або чотири None.

    `надлишок` — на скільки річ довша за її тіло від точки виміру; поділ тоді стоїть на
    підлозі. Розкид приходить із крамниці (`довжина_виробу_розкид_см`): розмірна сітка
    дає свою довжину на кожен розмір, а свого розміру жінка коду не називала."""
    дов, точка = r.get("довжина_виробу_см"), r.get("довжина_виробу_точка")
    якір = H.get(точка) if точка else None
    зріст = H.get("маківка")
    if дов is None or якір is None or not зріст:
        return None, None, None, None
    низ = round(float(якір) - float(дов), 1)
    if низ > float(зріст) or низ < -_НАДЛИШОК_МЕЖА_СМ:
        return None, None, None, None
    return (max(0.0, низ), float(r.get("довжина_виробу_розкид_см") or 0.0) or None, точка,
            (round(-низ, 1) if низ < 0.0 else None))


def клас_довжини(низ_см, H):
    """(код рівня, на скільки см поділ відійшов від центру його зони) або (None, None).

    Це `_РІВЕНЬ_ЗОНА`, читаний НАЗАД: словник один, тож клас із виміру й клас зі слова
    не можуть розійтися визначенням. Клас — найближчий центр, і відступ віддається
    поруч: він і є мірою того, чи поділ справді в цьому класі, чи між двома."""
    if низ_см is None:
        return None, None
    кандидати = []
    for рів in _РІВЕНЬ_ЗОНА:
        ц, рз = висота_рівня(рів, H)
        if ц is not None:
            кандидати.append((abs(низ_см - ц), -(рз or 0.0), рів))
    if not кандидати:
        return None, None
    # РІВНА ВІДСТАНЬ — ШИРША ЗОНА. «щиколотка» і «максі» стоять на тому самому центрі
    # (щиколотка тіла), і поділ на підлозі рівновіддалений від обох; ширша зона — менш
    # рішуча заява, і саме її має віддавати вимір, коли вибору між двома нема.
    від, _, рів = min(кандидати)
    return рів, round(від, 1)


# ── K-ACC-12: КРОК, ЯКОГО НЕ БУЛО ВЗАГАЛІ (22.09.2026) ──────────────────────
# ЩО ЦЕ МІНЯЄ В РІШЕННІ. Правило K-ACC-12 із серпня чекало на «рішення
# композитора», а композитор такого кроку НЕ МАВ: `місце` лишалось None у 100 %
# багатомісних речей, і над кожною сумкою кожного образу виходив рядок «місце
# для «Сумка жіноча» не обране». Тепер крок існує, і в нього рівно три гілки,
# кожна зі слідом у `місце_джерело`:
#   1. картка сама назвала спосіб носіння (`фід_атрибути.спосіб_носіння` →
#      рядок каталогу) — композитор його НЕ переобирає: твердження продавця
#      сильніше за наш здогад, і провенанс уже стоїть;
#   2. допустиме місце одне — вибору нема, і воно ставиться тут. Так живуть усі
#      одномісні речі («слот і місце збігаються») і замкнені шарфи, яким
#      конструкція лишила одне місце;
#   3. місць кілька, картка мовчить — `місце` лишається None, а `місце_джерело`
#      ставиться в None ЯВНО. Це не косметика: доти «вибір не зроблено» й «поля
#      в записі нема» були одним і тим самим `None`, тобто нерозрізненні.
# ЧОГО ТУТ НЕМА І НЕ БУДЕ: мовчазного дефолту. «шия» для хустки був знятий
# 26.08.2026 саме тому, що звільняв колірне вікно верху на підставі рішення,
# якого ніхто не ухвалював. Гілка 3 — це чесне «не знаю», і рядок для жінки
# питає рівно про це (`аксесуари_структура.місце_не_обране`).
def обрати_місце(r):
    """Крок вибору місця для ОДНІЄЇ речі. Повертає поля, які доклеюються до неї."""
    if r.get("місце"):
        return dict(місце_джерело=(r.get("місце_джерело")
                                   or "слот і місце збігаються: річ одномісна"))
    місця = tuple(r.get("місця") or ())
    if len(місця) == 1:
        return dict(місце=місця[0],
                    місце_джерело="допустиме місце одне — вибирати нема з чого")
    return dict(місце_джерело=None)


def _у_річ(r, слот, тіло, дистанція=None):
    """Кандидат каталогу → річ із геометрією, яку споживають шари посадки й силуету.

    ⚠ ПЛОЩА ТУТ ВИГАДАНА, І ЦЕ НАЗВАНО (вимір 08.09.2026). `площа=1/3` і `near`
    зі слотової таблиці — не вимір, а рівна частка: сумка й пальто виходять
    звідси однаковими за площею. Поля `джерело_площі` ця функція НЕ ставить
    навмисно, і саме тому `суд_образу.review` на такому вході чесно утримує пʼять
    колірних правил (K-COL-01/02/05/06, K-COMP-03) замість судити за вигадкою.
    ВИМІРЯНО на живому шляху (`перевірити_від_моделі`, каталог_повний,
    «офіс · 18 °C»): усі чотири речі образу дістають площу 0.333 і
    `джерело_площі=None`, у виході стоїть одна знахідка «площі не виміряні», і
    колірний шар над образом МОДЕЛІ мовчить цілком.
    ЧОГО ТУТ НЕМА І ЧОМУ. Порахувати площі з геометрії можна (`areas.образ_з_
    геометрії`), але верх_см/низ_см тут самі здебільшого з ДЕФОЛТУ СЛОТА (поле
    `край_джерело`): довжину речі фід дає лише для 22 % SKU, а для сумки й
    аксесуарів слотової карти нема взагалі. Площа, порахована з дефолтної
    довжини, — та сама вигадка, лише дорожча, і вона зняла б утримання, тобто
    вимкнула б єдиний свідок. Рішення, звідки брати геометрію на живому шляху,
    винесене в A9 і не приймається мовчки тут."""
    # МЕТАЛ ПРИКРАСИ (29.08.2026). Без цього поля `суд_образу.метали` виходив на
    # порожньому списку над КОЖНИМ образом реального каталогу, і відповідь людини
    # на елісітації не мала з чим порівнюватись. `feed.метал` віддає None там, де
    # слова нема, — правило тоді мовчить, як і має.
    # П.14: `feed.метал` уже віддає None там, де слова нема, — мовчання правила
    # має рівно одну законну причину, і вона названа. `pass` додавав другу,
    # невідрізненну: поломку виміру.
    if not r.get("метал"):
        import feed as _Ф
        _м = _Ф.метал(r, слот)
        if _м: r = dict(r, метал=_м)
    # ── КРОК ВИБОРУ МІСЦЯ (22.09.2026, K-ACC-12) ─────────────────────────────
    # Він тут, бо `_у_річ` — ЄДИНИЙ шлях, яким рядок каталогу стає річчю образу:
    # і стенд (`стенд_знімок`), і живий суд (`суд_від_моделі.перевірити_від_
    # моделі`), і руки без каталогу проходять через нього. Крок, поставлений у
    # одному з трьох викликачів, був би кроком у одному з трьох виходів.
    r = dict(r, **обрати_місце(r))
    H = (тіло or {}).get("висоти") or {}
    гео = {"верх": (H.get("плечі"), H.get("стегна")),
           "низ": (H.get("талія"), H.get("коліно")),
           "сукня": (H.get("плечі"), H.get("коліно")),
           "комплект": (H.get("плечі"), H.get("коліно")),
           "взуття": (10.0, 0.0)}.get(слот, (None, None))
    # ДОВЖИНА В САНТИМЕТРАХ ФІД НЕ НЕСЕ: без неї краї беруться з дефолту слота. Це
    # ВХІД, а не вимір — і шар посадки мусить це бачити: без позначки K-FIT-03
    # видавав «край завершується на опуклості «стегна»» силою 1.0 для КОЖНОГО верху
    # ager (25/25 комбінацій, обидва колорити) — вимір над вигаданою довжиною,
    # тобто рівно те, що K-IO-05 зве декоративним слідом.
    # ── ДОВЖИНА ЗІ СЛОВА — ТРЕТЄ ДЖЕРЕЛО МІЖ «РІЧ» І «ДЕФОЛТ» (27.08.2026) ──────
    # Каталог жниварки несе РІВЕНЬ довжини для 1233 SKU (міді/міні/максі/до колін)
    # і слово в назві ще для сотень; доти K-FIT-03 виходив «утримано» в КОЖНОМУ
    # образі на реальному каталозі. Слово — це ЗОНА, не точка (той самий принцип,
    # що «слово кольору — зона, не центр»): рівень переводиться у сантиметри на
    # ЦЬОМУ тілі разом із похибкою `край_розкид_см`, і шар посадки судить зону, а
    # не її центр (fit.краї). Джерело «слово» стоїть окремо від «річ»: сила правил
    # над ним обмежена (T3 ≤ вимір).
    край_відомий = ("верх_см" in r and "низ_см" in r)
    # ── ДОВЖИНА ВИРОБУ В САНТИМЕТРАХ — ДРУГЕ ДЖЕРЕЛО, СИЛЬНІШЕ ЗА СЛОВО (Ф-9) ──
    # Порядок джерел краю: власна геометрія речі → ВИМІР крамниці (цей крок) → слово
    # крамниці → дефолт слота. Вимір стоїть вище за слово, бо слово — зона ±7 см, а
    # оголошена довжина — число з розміреною сіткою; `край_джерело="виріб"` тим самим
    # знімає з `fit.краї` і смугу слова, і зріз сили до `soft`.
    низ_вимір, розкид_вимір, точка_вимір, надлишок_вимір = (
        край_з_довжини(r, H) if (not край_відомий and H) else (None, None, None, None))
    # КЛАС ПОДІЛУ — ФАКТ ПРО ЦЕ ТІЛО, А НЕ ПРО РІЧ, і тому він рахується тут, а не в
    # каталозі: та сама сукня на 155 і на 175 см має різний клас. Поле поруч зі
    # словом крамниці (`довжина_рівень_крамниці`), а не замість нього — розбіг двох
    # називає `fit.довжина_проти_зросту`, і замовчувати його нема за чим.
    клас_вимір, відступ_вимір = клас_довжини(низ_вимір, H) if низ_вимір is not None else (None, None)
    # ── ПОДІЛ МІЖ ДВОМА КЛАСАМИ — ЧЕСНЕ «НЕ ЗНАЮ», А НЕ НАЙБЛИЖЧИЙ КЛАС ──────────
    # `_РІВЕНЬ_ЗОНА` — конвенція T3 з дірками: між паху (0,48·зріст) і коліном (0,285)
    # лежить одна зона «міні» ±8 см, тож поділ на 74 см при зрості 165 стоїть на 10,7 см
    # від центру «міні» і на 12,0 см від центру «стегно» — поза ОБОМА зонами. Назвати
    # його «міні» означало б вдати клас, якого вимір не показує. ВИМІРЯНО на каталозі:
    # так лежать 964 речі з 1 665 на зрості 165 см (58 %), тобто це не рідкість, а
    # властивість таблиці рівнів. Такий клас не пишеться в `довжина_рівень` і не
    # сперечається зі словом крамниці; сантиметри краю від цього не страждають — саме
    # їх і судить K-FIT-03.
    _рз_класу = висота_рівня(клас_вимір, H)[1] if клас_вимір else None
    між_класами = (відступ_вимір is not None and відступ_вимір > (_рз_класу or 0.0))
    низ_слово, розкид_слово = None, None
    if not край_відомий and низ_вимір is None and r.get("довжина_рівень") and H:
        низ_слово, розкид_слово = висота_рівня(r["довжина_рівень"], H)
    # ── РІЧ — ЗОНА, НЕ ТОЧКА (28.08.2026, graph.py) ──────────────────────────
    # Колір зі слова доти заходив у парні правила ТОЧКОЮ (центр вікна, розкид
    # None): дві «світло-сірих» — ΔE 0 за побудовою. Тепер слово несе свою
    # точність — півширину L-вікна — тим самим полем `розкид`, яким фото несе
    # розкид пікселів, і `_сила(розкид)` обмежує вердикт, коли маржа менша за неї.
    _розкид_слова = ГР.розкид_зі_слова(r) if r.get("розкид") is None else None
    _зона = dict(розкид=_розкид_слова, розкид_джерело="слово: півширина L-вікна") if _розкид_слова is not None else {}
    if r.get("джерело_кольору") == "назва_вікно" and r.get("вікно") and r.get("C_зона") is None:
        _зона["C_зона"] = (float(r["вікно"][2]), float(r["вікно"][3]))   # зона хроми слова — у бюджет K-COL-02
    # колір, якого ніхто не міряв і не назвав (її річ з фото без виміру): hex нижче — заглушка
    # ядра, моделі річ іде з «невідомо», суду — з вікном «колір невідомий» (Л-4)
    _колір_невідомий = _невідомий_колір(r) if not (r.get("hex") or r.get("lab")) else {}
    if низ_вимір is not None:
        # `довжина_рівень` заповнюється ВИМІРОМ лише там, де крамниця слова не дала й
        # де це слово взагалі можна ставити слотові (`feed.клас_довжини_для_слота` —
        # та сама умова, якою відсіюються слова крамниці). Інакше поле лишається як
        # було: слово крамниці — твердження продавця, і затирати його нашою
        # класифікацією означало б зробити розбіг двох джерел невидимим.
        import feed as _Ф2
        _рів = dict(довжина_клас_виміряний=клас_вимір, довжина_клас_відступ_см=відступ_вимір,
                    довжина_клас_між=між_класами)
        if (not r.get("довжина_рівень") and not між_класами
                and _Ф2.клас_довжини_для_слота(клас_вимір, слот)):
            _рів.update(довжина_рівень=клас_вимір,
                        довжина_джерело="вимір: довжина виробу проти зросту")
        return dict(r, слот=слот, верх_см=(гео[0] if слот != "взуття" else низ_вимір),
                    низ_см=низ_вимір, край_джерело="виріб",
                    край_розкид_см=розкид_вимір, край_точка_виміру=точка_вимір,
                    довжина_надлишок_см=надлишок_вимір,
                    площа=r.get("площа", 1.0 / 3),
                    near=r.get("near", _near_слота(слот, дистанція)),
                    hex=r.get("hex") or _hex_від_lab(r.get("lab")),
                    **_рів, **_зона, **_колір_невідомий)
    if низ_слово is not None:
        верх_слово = гео[0] if слот != "взуття" else низ_слово
        return dict(r, слот=слот, верх_см=верх_слово, низ_см=низ_слово,
                    край_джерело="слово", край_розкид_см=розкид_слово,
                    площа=r.get("площа", 1.0 / 3),
                    near=r.get("near", _near_слота(слот, дистанція)),
                    hex=r.get("hex") or _hex_від_lab(r.get("lab")), **_зона, **_колір_невідомий)
    return dict(r, слот=слот, верх_см=r.get("верх_см", гео[0]),
                низ_см=r.get("низ_см", гео[1]), **_зона,
                край_джерело=(r.get("край_джерело") or ("річ" if край_відомий else "дефолт слота")),
                площа=r.get("площа", 1.0 / 3),
                near=r.get("near", _near_слота(слот, дистанція)),
                # БУЛО: hex="#808080" для БУДЬ-ЯКОЇ речі без hex. Каталог несе lab,
                # не hex → КОЖНА річ ставала тим самим сірим, ΔL*=0, і K-COL-01
                # («тон-у-тон») блокував БУДЬ-ЯКИЙ образ у review, хоч композитор
                # вище ранжував по справжніх lab. Третій за день «фільтр в одній
                # гілці». Тепер hex виводиться зі свого lab; сірий лишається лише
                # коли нема ані hex, ані lab — і це видно, бо lab=None рідкість.
                hex=r.get("hex") or _hex_від_lab(r.get("lab")), **_колір_невідомий)


def _середня_відстань(комбо):
    """Середня `_відстань` до центрів вікон по речах комбінації; None без відстаней."""
    д = [r.get("_відстань") for r in комбо if r.get("_відстань") is not None]
    return round(sum(д) / len(д), 2) if д else None
