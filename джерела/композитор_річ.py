def _hex_від_lab(lab):
    """hex з lab речі; сірий #808080 лише коли lab нема.

    Сірий — ЗАГЛУШКА для ядра кольору (`outfit.елементи` без кольору речі не бере), а не
    колір речі: `_у_річ` ставить поруч `колір_невідомий`, і моделі річ їде зі словом
    «невідомо», без hex (`пакет_моделі._річ_пулу`, Л-4). Доти «тоді це видно» було
    неправдою: «світлі джинси кльош» з її фото без виміру йшли в пул і в промпт
    ремонту як `"hex": "#808080"` — 8 із 8 сирих промптів складання ноутбука 25.09."""
    if not lab: return "#808080"
    import colorspace as _cs
    r, g, b = (max(0.0, min(1.0, x)) for x in _cs.to_rgb(*lab))
    return "#%02x%02x%02x" % (round(r*255), round(g*255), round(b*255))


# ВІКНО «КОЛІР НЕВІДОМИЙ»: уся світлота, уся хрома, тон будь-який. Правила, що вміють
