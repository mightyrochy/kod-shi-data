def виразність(r):
    """Скільки «голосу» в речі: принт > хрома > нічого. Для вибору якоря (K-COMP-02).

    ДРУГИЙ ЧИТАЧ — `pipeline.риси_образу` (Т-10): ця ж шкала називає ГЕРОЯ образу
    моделі, а поріг, з якого річ ним стає, стоїть у `реєстр_правил.REGISTRY`
    («виразність_героя») зі своїм тіром. Шкала лишається тут і без поріга всередині:
    хто міряє — не той, хто вирішує, скільки досить."""
    в = 0.0
    if r.get("візерунок") not in (None, "", "solid", "однотон"): в += 1.0
    # Для інтервалу враховується лише гарантована нижня межа хроми.
    межі = _КР.межі_кольору(r)
    if межі is not None:
        в += min(1.0, межі[2] / 60.0)
    if str(r.get("текстура") or "") in ("satin", "patent", "smooth-shine", "knit-chunky", "tweed-boucle", "leather"): в += 0.5
    return в


