"""Задає точні часткові відображення граней з необмеженою хромою.

Скінченна C пробігає весь вихідний промінь. Нескінченність позначає
відкритий напрямок, а не колір; область визначає чинний renotation/XYZ.
Свідки не інтерполюються і не задають стелю C або оболонку продукту.
"""
import argparse
import importlib.util
import json
import math
from pathlib import Path


ШЛЯХ = Path(__file__).with_name("колір_сім_ї_скінченні.py")
СПЕЦИФІКАЦІЯ = importlib.util.spec_from_file_location("скінченні", ШЛЯХ)
ПОПЕРЕДНІЙ = importlib.util.module_from_spec(СПЕЦИФІКАЦІЯ)
СПЕЦИФІКАЦІЯ.loader.exec_module(ПОПЕРЕДНІЙ)
ОСНОВА = ПОПЕРЕДНІЙ.ОСНОВА
ВХІД = ОСНОВА.ВХІД
ВИХІД = Path(__file__).with_suffix(".json")


def обрано(грань):
    """Обирає H/V-грані з повним променем C, без ручних номерів."""
    if грань["вісь"] not in ("H", "V"):
        return False
    (a, b), (c, d) = грань["інтервали"]
    return (d == "+inf" and all(isinstance(x, (int, float)) and math.isfinite(x)
                               for x in (a, b, c, грань["координата"]))
            and a <= b and c > 0
            and (грань["вісь"] == "H" or 0 < грань["координата"] < 10))


def звірити_попереднє(бібліотека, вхід):
    """Звіряє транзитивні джерела та повноту попереднього обліку."""
    раніше, _ = ПОПЕРЕДНІЙ.звірити_попереднє(бібліотека, вхід)
    попереднє = json.loads(ПОПЕРЕДНІЙ.ВИХІД.read_text(encoding="utf-8"))
    номери = [x["грань"] for x in попереднє["грані"]]
    очікувані = {i for i, g in enumerate(вхід["межі"]) if ПОПЕРЕДНІЙ.обрано(g)}
    if len(номери) != len(set(номери)) or set(номери) != очікувані:
        raise ValueError("Інший клас попередніх скінченних граней")
    if попереднє["раніше"] != раніше:
        raise ValueError("Неузгоджений попередній облік скінченних граней")
    всі = раніше + номери + [x["грань"] for x in попереднє["відкладені"]]
    if sorted(всі) != list(range(len(вхід["межі"]))):
        raise ValueError("Пропуск або дубль у попередньому обліку")
    for запис in попереднє["грані"]:
        if запис["джерело"] != вхід["межі"][запис["грань"]]:
            raise ValueError("Інше джерело скінченної грані")
    for запис in попереднє["походження"] + попереднє["походження_перетворення"]:
        назва = запис["файл"]
        if назва.startswith("colour/"):
            шлях = Path(бібліотека.__file__).parent / назва.removeprefix("colour/")
        else:
            шлях = ВХІД.parent / назва
            if not шлях.is_file():
                шлях = ОСНОВА.ДЖЕРЕЛА / назва
        if ОСНОВА.походження([(назва, шлях)])[0] != запис:
            raise ValueError(f"Застаріле походження: {назва}")
    return sorted(раніше + номери), попереднє


def координати(грань, u, C):
    """Розгортає скінченну точку повної напівсмуги H/V × C."""
    if not обрано(грань):
        raise ValueError("Інший клас грані")
    if not all(math.isfinite(x) for x in (u, C)):
        raise ValueError("Непридатний параметр грані")
    (a, b), (c, _) = грань["інтервали"]
    if not a <= u <= b or C < c:
        raise ValueError("Поза вихідною гранню")
    if грань["вісь"] == "H":
        return грань["координата"], u, C
    return u, грань["координата"], C


def перетворити_грань(перетворити, грань, u, C):
    """Дає точний образ або явну відмову для довільної скінченної C.

    Предикат V та перетворення — попередні методи. Очікувані відмови
    renotation/XYZ задають доповнення області; неочікувані поширюються.
    """
    H, V, C = координати(грань, u, C)
    запис = {"HVC": [H, V, C]}
    if not ПОПЕРЕДНІЙ.визначено_V(V):
        return dict(запис, стан="невизначено", причина="V поза овоїдами чинного методу")
    try:
        lab, θLC = перетворити(H, V, C)
    except (AssertionError, ValueError) as помилка:
        return dict(запис, стан="невизначено", причина="renotation або непридатний XYZ",
                    відмова=str(помилка))
    return dict(запис, стан="визначено", Lab=lab, θLC=θLC)


def параметри_проб(грань):
    """Дає скінченних свідків напівсмуги, які не обмежують область C."""
    (a, b), (c, _) = грань["інтервали"]
    значення = {a, (a + b) / 2, b}
    if грань["вісь"] == "H":
        значення.update(x for x in (0.5, 0.9995, 1, 9, 9.5, 9.9995) if a <= x <= b)
    хроми = (c, c + 1, c + 4, c + 16, c + 64, c + 1024)
    return [(u, C) for u in sorted(значення) for C in хроми]


def породити():
    """Породжує всі необмежені часткові поверхні й звіряє облік 234 граней."""
    бібліотека = ОСНОВА.залежності()
    перетворити = ОСНОВА.зробити_перетворення(бібліотека)
    вхід = json.loads(ВХІД.read_text(encoding="utf-8"))
    раніше, попереднє = звірити_попереднє(бібліотека, вхід)
    артефакт = {
        "формат": 1, "версії": ОСНОВА.ВЕРСІЇ,
        "походження": ОСНОВА.походження([
            (Path(__file__).name, __file__), (ШЛЯХ.name, ШЛЯХ),
            (ПОПЕРЕДНІЙ.ВИХІД.name, ПОПЕРЕДНІЙ.ВИХІД)]),
        "походження_перетворення": попереднє["походження"] + попереднє["походження_перетворення"],
        "статус": "Точне процедурне часткове відображення; не сітка, не оболонка й не вхід продукту",
        "джерело_методу": попереднє["джерело_методу"],
        "метод": "перетворити_грань(ОСНОВА.зробити_перетворення(Colour), джерело, u, C)",
        "область": "Повна напівсмуга джерела зі скінченною C; образ рівно при стан=визначено",
        "нескінченність": "Відкритий напрямок променя, не параметр точки й не колір",
        "невизначено": "Доповнення визначеної області; координат Lab/θLC немає",
        "апроксимація": "Немає; свідки не інтерполюються й не задають меж області",
        "раніше": раніше, "грані": [], "відкладені": [],
    }
    for номер, грань in enumerate(вхід["межі"]):
        if номер in раніше:
            continue
        if not обрано(грань):
            raise ValueError(f"Необлікований клас грані {номер}")
        свідки = [перетворити_грань(перетворити, грань, u, C)
                  for u, C in параметри_проб(грань)]
        артефакт["грані"].append({
            "грань": номер, "джерело": грань,
            "параметри": ["V", "C"] if грань["вісь"] == "H" else ["H", "C"],
            "межі": грань["інтервали"], "замкненість": [[True, True], [True, False]],
            "свідки": свідки})
        прийнято = sum(x["стан"] == "визначено" for x in свідки)
        print(f"Грань {номер}: визначено {прийнято}, невизначено {len(свідки) - прийнято}", flush=True)
    return артефакт


def головна():
    """Записує або побайтово відтворює необмежені процедурні поверхні."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--записати", action="store_true")
    парсер.add_argument("--вихід", type=Path, default=ВИХІД)
    аргументи = парсер.parse_args()
    текст = json.dumps(ОСНОВА.округлити(породити()), ensure_ascii=False,
                       allow_nan=False, separators=(",", ":")) + "\n"
    if аргументи.записати:
        аргументи.вихід.write_text(текст, encoding="utf-8", newline="\n")
    elif not аргументи.вихід.exists() or аргументи.вихід.read_text(encoding="utf-8") != текст:
        парсер.exit(1, "Артефакт відсутній або відрізняється від виходу методу\n")


if __name__ == "__main__":
    головна()
