"""Породжує точні спільні поверхні сімей у координатах джерела Munsell H/V/C.

Це підготовка перенесення областей, не класифікатор продукту. Набір сімей
читається з таблиці корпусу; внутрішні стики клітинок однієї сім'ї зникають.
H циклічний, C необмежена: жодного обрізання за екранним гамутом тут немає.
Після цього потрібне перенесення всієї поверхні у θ/L*/C* з контролем похибки.
"""
import argparse
import csv
import hashlib
import itertools
import json
import math
from pathlib import Path
import re


ДЖЕРЕЛА = Path(__file__).resolve().parents[1]
ТАБЛИЦЯ = ДЖЕРЕЛА / "колір_сім_ї_вікна.md"
КЛІТИНКИ = ДЖЕРЕЛА / "дані_корпусу/ISCC-NBS_вікна.txt"
ВИХІД = Path(__file__).with_suffix(".json")
РЕЄСТР = {
    "область": {"t": "T3", "val": ((1, 101), (0, 10), (0, math.inf)),
                "прав": ["R-MUN-05", "R-MUN-06"],
                "джерело": "ISCC-NBS_вікна.txt: ASTM H [1,101), V [0,10], C [0,Inf)"},
}


def прочитати_сім_ї(текст):
    """Читає коди й номери блоків із єдиної таблиці, відкидаючи неоднозначність."""
    сім_ї, власники = [], {}
    for код, номери in re.findall(
            r"^\| `([a-z_]+)` \| [^|]+ \| ([\d–, ]+) \|", текст, re.M):
        if код in сім_ї:
            raise ValueError(f"Повтор коду сім'ї: {код}")
        сім_ї.append(код)
        for частина in номери.split(","):
            краї = [int(число) for число in частина.strip().split("–")]
            if len(краї) not in (1, 2) or краї[0] > краї[-1]:
                raise ValueError(f"Непридатний діапазон: {частина}")
            for номер in range(краї[0], краї[-1] + 1):
                if номер in власники:
                    raise ValueError(f"Повтор номера блока: {номер}")
                власники[номер] = код
    if not власники:
        raise ValueError("Немає таблиці сімей")
    return сім_ї, власники


def прочитати_клітинки(текст):
    """Читає повні прямокутні області, не змінюючи нескінченних меж хроми."""
    рядки = (рядок for рядок in текст.splitlines()
             if рядок.strip() and not рядок.lstrip().startswith("#"))
    клітинки = []
    for рядок in csv.DictReader(рядки, delimiter="\t"):
        межі = tuple((float(рядок[вісь + "min"]), float(рядок[вісь + "max"]))
                     for вісь in "HVC")
        for (низ, верх), (мінімум, максимум) in zip(межі, РЕЄСТР["область"]["val"]):
            if not мінімум <= низ < верх <= максимум or not math.isfinite(низ):
                raise ValueError(f"Непридатна клітинка: {рядок}")
        клітинки.append((int(рядок["Number"]), межі))
    if not клітинки:
        raise ValueError("Немає клітинок джерела")
    return клітинки


def розбити_простір(клітинки, власники):
    """Будує точне спільне розбиття й відмовляє при прогалині або перекритті.

    Усі зміни належності лежать на координатних площинах меж клітинок.
    Тому заповнення всіх відкритих комірок цього розбиття вичерпне;
    жодна випадкова вибірка чи штучний центр нескінченного інтервалу не потрібні.
    """
    if {номер for номер, _ in клітинки} != set(власники):
        raise ValueError("Номери блоків таблиці й джерела не збігаються")
    осі = [sorted({край for _, межі in клітинки for край in межі[вісь]})
           for вісь in range(3)]
    if tuple((вісь[0], вісь[-1]) for вісь in осі) != РЕЄСТР["область"]["val"]:
        raise ValueError("Джерело не покриває повну область H/V/C")
    індекси = [{значення: індекс for індекс, значення in enumerate(вісь)} for вісь in осі]
    сітка = {}
    for номер, межі in клітинки:
        діапазони = [range(індекси[вісь][низ], індекси[вісь][верх])
                     for вісь, (низ, верх) in enumerate(межі)]
        for адреса in itertools.product(*діапазони):
            if адреса in сітка:
                raise ValueError(f"Перекриття клітинок: {адреса}, блок {номер}")
            сітка[адреса] = власники[номер]
    розмір = math.prod(len(вісь) - 1 for вісь in осі)
    if len(сітка) != розмір:
        raise ValueError(f"Прогалина джерела: заповнено {len(сітка)} з {розмір}")
    return осі, сітка


def об_єднати_прямокутники(ділянки):
    """Зливає суміжні ділянки однієї орієнтованої межі без заповнення увігнутостей."""
    решта = set(ділянки)
    while решта:
        початок, рядок = min(решта)
        кінець = початок + 1
        while (кінець, рядок) in решта:
            кінець += 1
        верх = рядок + 1
        while all((стовпець, верх) in решта for стовпець in range(початок, кінець)):
            верх += 1
        решта.difference_update(itertools.product(range(початок, кінець), range(рядок, верх)))
        yield ((початок, кінець), (рядок, верх))


def побудувати_межі(осі, сітка):
    """Породжує кожну спільну межу один раз із сім'ями з обох її боків.

    На стику H=1/101 мінусовий бік — останній аркуш, плюсовий — перший.
    Зовнішній бік V=0, V=10 та C=0 — None. Нескінченність не є площиною;
    грані H/V із необмеженим C зберігають нескінченний кінець інтервалу.
    """
    групи = {}
    розміри = [len(вісь) - 1 for вісь in осі]
    for адреса, сім_я in sorted(сітка.items()):
        for вісь in range(3):
            сусід = list(адреса)
            сусід[вісь] -= 1
            if вісь == 0:
                сусід[вісь] %= розміри[вісь]
            попередня = сітка.get(tuple(сусід))
            інші = [номер for номер in range(3) if номер != вісь]
            ділянка = tuple(адреса[номер] for номер in інші)
            if попередня != сім_я:
                ключ = (вісь, адреса[вісь], попередня, сім_я)
                групи.setdefault(ключ, set()).add(ділянка)
            if вісь == 1 and адреса[вісь] == розміри[вісь] - 1:
                ключ = (вісь, розміри[вісь], сім_я, None)
                групи.setdefault(ключ, set()).add(ділянка)
    межі = []
    for (вісь, рівень, зліва, справа), ділянки in sorted(
            групи.items(), key=lambda пара: tuple("" if к is None else str(к) for к in пара[0])):
        інші = [номер for номер in range(3) if номер != вісь]
        for прямокутник in об_єднати_прямокутники(ділянки):
            інтервали = [[осі[номер][низ], осі[номер][верх]]
                         for номер, (низ, верх) in zip(інші, прямокутник)]
            межі.append({"вісь": "HVC"[вісь], "координата": осі[вісь][рівень],
                         "інтервали": інтервали, "сім_ї": [зліва, справа]})
    return межі


def підготувати_значення(значення):
    """Кодує необмежений кінець як рядок, не як невалідне JSON-число Infinity."""
    if isinstance(значення, float) and math.isinf(значення):
        return "+inf"
    if isinstance(значення, list):
        return [підготувати_значення(елемент) for елемент in значення]
    if isinstance(значення, dict):
        return {ключ: підготувати_значення(елемент) for ключ, елемент in значення.items()}
    return значення


def породити():
    """Виводить поверхні з джерел разом із походженням та лічбою області."""
    таблиця = ТАБЛИЦЯ.read_text(encoding="utf-8")
    текст = КЛІТИНКИ.read_text(encoding="utf-8")
    сім_ї, власники = прочитати_сім_ї(таблиця)
    клітинки = прочитати_клітинки(текст)
    осі, сітка = розбити_простір(клітинки, власники)
    return підготувати_значення({
        "формат": 1,
        "походження": [
            {"шлях": шлях.relative_to(ДЖЕРЕЛА).as_posix(),
             "sha256_lf": hashlib.sha256(вміст.encode("utf-8")).hexdigest()}
            for шлях, вміст in ((ТАБЛИЦЯ, таблиця), (КЛІТИНКИ, текст))],
        "простір": "Munsell ASTM H/V/C; H=1 тотожне H=101; +inf — необмежений кінець",
        "статус": "Межі джерела; не θ/L*/C*, не сили належності й не вхід продукту",
        "сім_ї": сім_ї,
        "блоків": len(власники), "клітинок": len(клітинки), "комірок": len(сітка),
        "порядок_інтервалів": {вісь: [інша for інша in "HVC" if інша != вісь] for вісь in "HVC"},
        "межі": побудувати_межі(осі, сітка),
    })


def головна():
    """Записує або звіряє відтворюваний артефакт без мережі й сторонніх бібліотек."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--записати", action="store_true")
    парсер.add_argument("--вихід", type=Path, default=ВИХІД)
    аргументи = парсер.parse_args()
    артефакт = породити()
    заголовок = {ключ: значення for ключ, значення in артефакт.items() if ключ != "межі"}
    текст = json.dumps(заголовок, ensure_ascii=False, allow_nan=False, indent=2)[:-2]
    грані = [json.dumps(грань, ensure_ascii=False, allow_nan=False) for грань in артефакт["межі"]]
    текст += ',\n  "межі": [\n    ' + ',\n    '.join(грані) + '\n  ]\n}\n'
    if аргументи.записати:
        аргументи.вихід.write_text(текст, encoding="utf-8", newline="\n")
    elif not аргументи.вихід.exists() or аргументи.вихід.read_text(encoding="utf-8") != текст:
        парсер.exit(1, "Артефакт відсутній або відрізняється від виходу методу\n")
    print(f"Сімей {len(артефакт['сім_ї'])}; блоків {артефакт['блоків']}; "
          f"клітинок {артефакт['клітинок']}; комірок {артефакт['комірок']}; "
          f"спільних/зовнішніх граней {len(артефакт['межі'])}")


if __name__ == "__main__":
    головна()
