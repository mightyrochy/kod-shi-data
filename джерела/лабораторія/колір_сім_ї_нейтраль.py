"""Переносить повну C=0-грань у параметричну нейтральну криву Lab.

H згортається, θ відсутній. Lab та залишкова C* зберігають чинну
renotation/адаптацію; крива не є замкненою оболонкою сімей продукту.
"""
import argparse
from functools import lru_cache
import importlib.util
import inspect
import json
import math
from pathlib import Path


ШЛЯХ = Path(__file__).with_name("колір_сім_ї_контури_hv.py")
СПЕЦИФІКАЦІЯ = importlib.util.spec_from_file_location("контури_hv", ШЛЯХ)
ПОПЕРЕДНІЙ = importlib.util.module_from_spec(СПЕЦИФІКАЦІЯ)
СПЕЦИФІКАЦІЯ.loader.exec_module(ПОПЕРЕДНІЙ)
ОСНОВА = ПОПЕРЕДНІЙ.ОСНОВА
ВХІД = ОСНОВА.ВХІД
ВИХІД = Path(__file__).with_suffix(".json")

from colorspace import адаптувати_освітлювач


def зробити_перетворення(бібліотека):
    """Дає нейтральний Lab без вигаданого H чи кута θ.

    XYZ→Lab під C виконує Colour, адаптацію C→D65 — чинний модуль
    простору. Це той самий шлях, що у хроматичних граней, з проміжним
    Lab під C замість повторення матриць Bradford.
    """
    білий = бібліотека.XYZ_to_xy(ОСНОВА.БІЛІ["C"])

    @lru_cache(maxsize=None)
    def перетворити(V):
        """Читає ASTM-нейтраль на всьому замкненому інтервалі V=0…10."""
        if not math.isfinite(V) or not 0 <= V <= 10:
            raise ValueError("Нейтральна V поза [0,10]")
        xyY = бібліотека.notation.munsell_colour_to_xyY(f"N{V:.12g}")
        xyz = бібліотека.xyY_to_XYZ(xyY)
        lab = адаптувати_освітлювач(бібліотека.XYZ_to_Lab(xyz, illuminant=білий))
        if not all(math.isfinite(x) for x in lab):
            raise ValueError("Непридатний нейтральний Lab")
        L, C, _ = ОСНОВА.lch(lab)
        return tuple(lab), (None, L, C)

    return перетворити


def похибки(точне, lab):
    """Міряє Lab/L*/C* без кутової похибки для невизначеного θ."""
    L, C, _ = ОСНОВА.lch(lab)
    return math.dist(точне[0], lab), abs(точне[1][1] - L), abs(точне[1][2] - C)


def наблизити(вузли, частка):
    """Інтерполює Lab між двома вузлами нейтральної кривої."""
    return tuple((1 - частка) * x + частка * y
                 for x, y in zip(вузли[0][0], вузли[1][0]))


def виміряти(перетворити, межі, вузли, частки):
    """Звіряє лінійну хорду з прямим методом у заданих частках V."""
    низ, верх = межі
    максимум = [0.0] * 3
    for частка in частки:
        точне = перетворити(низ + частка * (верх - низ))
        максимум = list(map(max, максимум, похибки(точне, наблизити(вузли, частка))))
    return максимум


def породити_відрізки(перетворити, межі, глибина=0):
    """Ділить повний інтервал V до проходження числових цілей Lab/L*/C*."""
    вузли = [перетворити(V) for V in межі]
    контроль = виміряти(перетворити, межі, вузли, (0.25, 0.5, 0.75))
    цілі = [ОСНОВА.РЕЄСТР["похибка"]["val"][i] for i in (0, 2, 3)]
    if all(x <= ціль / 2 for x, ціль in zip(контроль, цілі)):
        перевірка = виміряти(перетворити, межі, вузли,
                            (0.211324865405187, 0.788675134594813))
        if any(x > ціль for x, ціль in zip(перевірка, цілі)):
            raise ValueError(f"Відкладена проба нейтралі не пройшла: {межі}")
        yield {"V": межі, "вузли": вузли, "контроль": контроль, "перевірка": перевірка}
        return
    if глибина >= ОСНОВА.РЕЄСТР["глибина"]["val"]:
        raise ValueError(f"Не досягнуто числової цілі нейтралі: {межі}")
    низ, верх = межі
    середина = (низ + верх) / 2
    yield from породити_відрізки(перетворити, (низ, середина), глибина + 1)
    yield from породити_відрізки(перетворити, (середина, верх), глибина + 1)


def звірити_попереднє(бібліотека, вхід):
    """Звіряє попередні C/H/V-грані та транзитивне походження їхніх методів."""
    C = json.loads(ОСНОВА.ВИХІД.read_text(encoding="utf-8"))
    HV = json.loads(ПОПЕРЕДНІЙ.ВИХІД.read_text(encoding="utf-8"))
    готові = C["грані"] + HV["грані"]
    очікувані = {i for i, грань in enumerate(вхід["межі"])
                 if ПОПЕРЕДНІЙ.причина_відкладення(грань) is None}
    номери = [x["грань"] for x in готові]
    if len(set(номери)) != len(номери) or set(номери) != очікувані:
        raise ValueError("Попередні виходи не покривають рівно класи C/H/V")
    if sorted(HV["раніше"]) != sorted(x["грань"] for x in C["грані"]):
        raise ValueError("Облік попередніх C-граней не узгоджений")
    if sorted(номери + [x["грань"] for x in HV["відкладені"]]) != list(range(len(вхід["межі"]))):
        raise ValueError("Попередній облік не охоплює всі вихідні грані")
    for запис in готові:
        if запис["джерело"] != вхід["межі"][запис["грань"]]:
            raise ValueError("Інше джерело попередньої грані")
    походження = C["походження"] + HV["походження"] + HV["походження_перетворення"]
    for запис in походження:
        назва = запис["файл"]
        if назва.startswith("colour/"):
            шлях = Path(бібліотека.__file__).parent / назва.removeprefix("colour/")
        else:
            шлях = ВХІД.parent / назва
            if not шлях.is_file():
                шлях = ОСНОВА.ДЖЕРЕЛА / назва
        if ОСНОВА.походження([(назва, шлях)])[0] != запис:
            raise ValueError(f"Застаріле походження: {назва}")
    return sorted(номери), походження


def породити():
    """Породжує всі C=0-грані з повним обліком поверхонь джерела."""
    бібліотека = ОСНОВА.залежності()
    перетворити = зробити_перетворення(бібліотека)
    вхід = json.loads(ВХІД.read_text(encoding="utf-8"))
    раніше, походження = звірити_попереднє(бібліотека, вхід)
    from colour.models import cie_lab
    from colour.colorimetry import luminance
    артефакт = {
        "формат": 1, "версії": ОСНОВА.ВЕРСІЇ,
        "походження": ОСНОВА.походження([
            (ВХІД.name, ВХІД), (Path(__file__).name, __file__),
            (ПОПЕРЕДНІЙ.ВИХІД.name, ПОПЕРЕДНІЙ.ВИХІД),
            ("colour/models/cie_lab.py", inspect.getfile(cie_lab)),
            ("colour/colorimetry/luminance.py", inspect.getfile(luminance))]),
        "походження_перетворення": походження,
        "статус": "Лабораторна нейтральна крива; похибка вибіркова; не вхід продукту",
        "метод": "Colour N(V) ASTM → XYZ → Colour Lab під C → чинний Bradford D65",
        "подання": "H згорнуто; V замкнено; вузол [Lab,[null,L*,C*]]; інтерполюється Lab; θ невизначений за C джерела=0, залишкова C* збережена",
        "порядок_похибок": ["ΔLab76", "L*", "C*"],
        "цілі_похибки": [ОСНОВА.РЕЄСТР["похибка"]["val"][i] for i in (0, 2, 3)],
        "раніше": раніше, "грані": [], "відкладені": [],
    }
    for номер, грань in enumerate(вхід["межі"]):
        if номер in раніше:
            continue
        if грань["вісь"] != "C" or грань["координата"] != 0:
            артефакт["відкладені"].append({
                "грань": номер, "причина": ПОПЕРЕДНІЙ.причина_відкладення(грань)})
            continue
        H, V = грань["інтервали"]
        if H != [1, 101] or not 0 <= V[0] < V[1] <= 10:
            raise ValueError("Неочікувана область нейтральної грані")
        відрізки = []
        for межі in ОСНОВА.поділити(V, range(11)):
            відрізки.extend(породити_відрізки(перетворити, межі))
        артефакт["грані"].append({"грань": номер, "джерело": грань,
                                  "вимірність": 1, "відрізки": відрізки})
    if not артефакт["грані"]:
        raise ValueError("Джерело не має нейтральної грані")
    return артефакт


def головна():
    """Записує або відтворює повну нейтральну криву лабораторії."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--записати", action="store_true")
    парсер.add_argument("--вихід", type=Path, default=ВИХІД)
    аргументи = парсер.parse_args()
    артефакт = ОСНОВА.округлити(породити())
    текст = json.dumps(артефакт, ensure_ascii=False, allow_nan=False, separators=(",", ":")) + "\n"
    if аргументи.записати:
        аргументи.вихід.write_text(текст, encoding="utf-8", newline="\n")
    elif not аргументи.вихід.exists() or аргументи.вихід.read_text(encoding="utf-8") != текст:
        парсер.exit(1, "Артефакт відсутній або відрізняється від виходу методу\n")
    print(f"Нейтральних граней {len(артефакт['грані'])}; раніше {len(артефакт['раніше'])}; відкладено {len(артефакт['відкладені'])}")


if __name__ == "__main__":
    головна()
