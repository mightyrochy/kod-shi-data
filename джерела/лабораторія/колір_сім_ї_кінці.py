"""Описує перетин усіх V=0/10-граней з областю чинного renotation.

За додатної C метод не визначений на цих площинах; C=0 дає
кінці вже перенесеної нейтральної кривої. Це облік часткового
відображення, не нові кольорові поверхні або замкнена оболонка.
"""
import argparse
from functools import lru_cache
import importlib.util
import json
import math
from pathlib import Path


ШЛЯХ = Path(__file__).with_name("колір_сім_ї_нейтраль.py")
СПЕЦИФІКАЦІЯ = importlib.util.spec_from_file_location("нейтраль", ШЛЯХ)
НЕЙТРАЛЬ = importlib.util.module_from_spec(СПЕЦИФІКАЦІЯ)
СПЕЦИФІКАЦІЯ.loader.exec_module(НЕЙТРАЛЬ)
ОСНОВА = НЕЙТРАЛЬ.ОСНОВА
ВХІД = НЕЙТРАЛЬ.ВХІД
ВИХІД = Path(__file__).with_suffix(".json")


def зробити_перетворення(бібліотека):
    """Дає тільки визначені нейтральні точки на площинах V=0/10.

    Colour xy_from_renotation_ovoid допускає лише цілі V=1…9;
    хроматична гілка обох кінців звертається до цього методу.
    Додатну C не занулюємо й не замінюємо граничним кольором.
    """
    нейтраль = НЕЙТРАЛЬ.зробити_перетворення(бібліотека)

    @lru_cache(maxsize=None)
    def перетворити(H, V, C):
        """Відхиляє позаобласний вхід до читання нейтральної кривої."""
        if not all(math.isfinite(x) for x in (H, V, C)):
            raise ValueError("Непридатна координата кінця")
        if not 1 <= H <= 101 or V not in (0, 10) or C < 0:
            raise ValueError("Поза класом кінців V=0/10")
        if C > 0:
            raise ValueError("Renotation не визначений за V=0/10 та C>0")
        return нейтраль(V)

    return перетворити


def звірити_попереднє(бібліотека, вхід):
    """Звіряє весь попередній облік і походження до використання його кінців."""
    раніше, походження = НЕЙТРАЛЬ.звірити_попереднє(бібліотека, вхід)
    нейтраль = json.loads(НЕЙТРАЛЬ.ВИХІД.read_text(encoding="utf-8"))
    очікувані = {i for i, грань in enumerate(вхід["межі"])
                 if грань["вісь"] == "C" and грань["координата"] == 0}
    номери = [x["грань"] for x in нейтраль["грані"]]
    if len(set(номери)) != len(номери) or set(номери) != очікувані:
        raise ValueError("Попередній вихід не покриває рівно нейтральний клас")
    if нейтраль["раніше"] != раніше:
        raise ValueError("Неузгоджений облік перед нейтральною кривою")
    всі = раніше + номери + [x["грань"] for x in нейтраль["відкладені"]]
    if sorted(всі) != list(range(len(вхід["межі"]))):
        raise ValueError("Нейтральний облік не охоплює всі вихідні грані")
    if нейтраль["походження_перетворення"] != походження:
        raise ValueError("Інше транзитивне походження нейтралі")
    for запис in нейтраль["походження"]:
        назва = запис["файл"]
        if назва.startswith("colour/"):
            шлях = Path(бібліотека.__file__).parent / назва.removeprefix("colour/")
        else:
            шлях = ВХІД.parent / назва
        if ОСНОВА.походження([(назва, шлях)])[0] != запис:
            raise ValueError(f"Застаріле походження нейтралі: {назва}")
    for запис in нейтраль["грані"]:
        джерело = вхід["межі"][запис["грань"]]
        if запис["джерело"] != джерело or запис["вимірність"] != 1:
            raise ValueError("Інше джерело або вимірність нейтральної кривої")
    return sorted(раніше + номери), нейтраль


def подати_грань(грань, перетворити, нейтраль):
    """Описує повний визначений і невизначений перетини V=0/10-грані."""
    if грань["вісь"] != "V" or грань["координата"] not in (0, 10):
        raise ValueError("Очікується повна грань на V=0/10")
    H, C = грань["інтервали"]
    верх = math.inf if C[1] == "+inf" else C[1]
    if not (all(math.isfinite(x) for x in H) and 1 <= H[0] < H[1] <= 101
            and math.isfinite(C[0]) and 0 <= C[0] < верх
            and (C[1] == "+inf" or math.isfinite(верх))):
        raise ValueError("Непридатні параметричні межі кінця")
    запис = {
        "джерело": грань,
        "область": {
            "визначено": [],
            "невизначено": [{"H": H, "C": C,
                             "замкненість_C": [C[0] > 0, C[1] != "+inf"]}],
        },
        "образ": [],
    }
    if C[0] > 0:
        запис["статус"] = "порожній перетин з областю методу"
        return запис
    V = грань["координата"]
    вузол = перетворити(H[0], V, 0)
    посилання = []
    for попередня in нейтраль["грані"]:
        if not (попередня["джерело"]["інтервали"][0][0] <= H[0]
                and попередня["джерело"]["інтервали"][0][1] >= H[1]):
            continue
        for відрізок in попередня["відрізки"]:
            for край, попередній in zip(відрізок["V"], відрізок["вузли"]):
                if край == V and ОСНОВА.округлити(вузол) == попередній:
                    посилання.append({"грань": попередня["грань"], "V": V})
    if len(посилання) != 1:
        raise ValueError("Нема однозначного тотожного кінця нейтральної кривої")
    запис["статус"] = "нейтральна точка; решта поза областю методу"
    запис["область"]["визначено"] = [{"H": H, "C": [0, 0],
                                      "замкненість_C": [True, True]}]
    запис["образ"] = [{"вимірність": 0, "вузол": вузол,
                       "нейтраль": посилання[0]}]
    return запис


def породити():
    """Опрацьовує всі кінцеві V-грані без ручних номерів або стелі C."""
    бібліотека = ОСНОВА.залежності()
    перетворити = зробити_перетворення(бібліотека)
    вхід = json.loads(ВХІД.read_text(encoding="utf-8"))
    раніше, нейтраль = звірити_попереднє(бібліотека, вхід)
    артефакт = {
        "формат": 1, "версії": ОСНОВА.ВЕРСІЇ,
        "походження": ОСНОВА.походження([
            (ВХІД.name, ВХІД), (Path(__file__).name, __file__),
            (ШЛЯХ.name, ШЛЯХ), (НЕЙТРАЛЬ.ВИХІД.name, НЕЙТРАЛЬ.ВИХІД)]),
        "походження_перетворення": (нейтраль["походження"]
                                     + нейтраль["походження_перетворення"]),
        "статус": "Лабораторний облік області методу; не замкнена оболонка й не вхід продукту",
        "метод": "Colour 0.4.6: на V=0/10 визначено лише C=0; нейтраль — попередній метод",
        "підстава": "Хроматичний munsell_specification_to_xyY викликає xy_from_renotation_ovoid з цілим V=0/10, поза його [1,9]; normalise_munsell_specification переводить рівно C=0 у нейтраль",
        "джерело_методу": "https://colour.readthedocs.io/en/v0.4.6/_modules/colour/notation/munsell.html#xy_from_renotation_ovoid",
        "подання": "Повні замкнені H; C з явними кінцями; +inf відкрита; поза областю немає координат; у точках θ=null, залишкова C* збережена",
        "раніше": раніше, "грані": [], "відкладені": [],
    }
    for номер, грань in enumerate(вхід["межі"]):
        if номер in раніше:
            continue
        if грань["вісь"] != "V" or грань["координата"] not in (0, 10):
            артефакт["відкладені"].append({
                "грань": номер,
                "причина": НЕЙТРАЛЬ.ПОПЕРЕДНІЙ.причина_відкладення(грань)})
            continue
        запис = подати_грань(грань, перетворити, нейтраль)
        запис["грань"] = номер
        артефакт["грані"].append(запис)
    точки = sum(bool(x["образ"]) for x in артефакт["грані"])
    артефакт["підсумок"] = {
        "попередніх_граней": len(раніше),
        "точкових_перетинів": точки,
        "порожніх_перетинів": len(артефакт["грані"]) - точки,
        "відкладено": len(артефакт["відкладені"]),
    }
    return артефакт


def головна():
    """Записує або побайтово відтворює облік кінців V=0/10."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--записати", action="store_true")
    парсер.add_argument("--вихід", type=Path, default=ВИХІД)
    аргументи = парсер.parse_args()
    артефакт = ОСНОВА.округлити(породити())
    текст = json.dumps(артефакт, ensure_ascii=False, allow_nan=False, separators=(",", ":")) + "\n"
    if аргументи.записати:
        аргументи.вихід.write_text(текст, encoding="utf-8", newline="\n")
    elif not аргументи.вихід.exists() or аргументи.вихід.read_text(encoding="utf-8") != текст:
        парсер.exit(1, "Артефакт відсутній або відрізняється від виходу методу\n")
    print(f"Кінцевих граней {len(артефакт['грані'])}; {артефакт['підсумок']}")


if __name__ == "__main__":
    головна()
