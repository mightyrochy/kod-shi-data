"""Переносить спільні ребра H/V/C точними частковими кривими Lab.

Один читач ребра обслуговує всі суміжні грані. Нейтральні вершини
ототожнені за V, H-ребра на C=0 вироджені. Область визначає попередній
renotation; це не узгодження сіток, не неперервна замкнена оболонка.
"""
import argparse
from collections import Counter
from functools import lru_cache
import importlib.util
import json
import math
from pathlib import Path


def завантажити(назва):
    """Читає попередній лабораторний метод без входу в ядро продукту."""
    шлях = Path(__file__).with_name(назва + ".py")
    специфікація = importlib.util.spec_from_file_location(назва, шлях)
    модуль = importlib.util.module_from_spec(специфікація)
    специфікація.loader.exec_module(модуль)
    return модуль


ЗШИВАННЯ = завантажити("колір_сім_ї_зшивання")
ПОПЕРЕДНІЙ = завантажити("колір_сім_ї_необмежені")
СКІНЧЕННІ = ПОПЕРЕДНІЙ.ПОПЕРЕДНІЙ
НЕЙТРАЛЬ = СКІНЧЕННІ.ПОПЕРЕДНІЙ.ПОПЕРЕДНІЙ.НЕЙТРАЛЬ
ОСНОВА = ПОПЕРЕДНІЙ.ОСНОВА
ВИХІД = Path(__file__).with_suffix(".json")


def звірити_джерела(бібліотека):
    """Відмовляє при застарілих поверхнях, зшиванні чи перетворенні."""
    текст = ЗШИВАННЯ.ВИХІД.read_text(encoding="utf-8")
    комплекс = json.loads(текст)
    if текст != ЗШИВАННЯ.серіалізувати(ЗШИВАННЯ.породити()):
        raise ValueError("Застаріле зшивання джерела")
    вхід = json.loads(ОСНОВА.ВХІД.read_text(encoding="utf-8"))
    раніше, _ = ПОПЕРЕДНІЙ.звірити_попереднє(бібліотека, вхід)
    попереднє = json.loads(ПОПЕРЕДНІЙ.ВИХІД.read_text(encoding="utf-8"))
    номери = [x["грань"] for x in попереднє["грані"]]
    очікувані = [i for i, g in enumerate(вхід["межі"]) if ПОПЕРЕДНІЙ.обрано(g)]
    if (sorted(номери) != очікувані or попереднє["раніше"] != раніше
            or попереднє["відкладені"] or sorted(раніше + номери) != list(range(len(вхід["межі"])))):
        raise ValueError("Неповний облік попередніх поверхонь")
    for запис in попереднє["грані"]:
        if запис["джерело"] != вхід["межі"][запис["грань"]]:
            raise ValueError("Інше джерело попередньої поверхні")
    походження = попереднє["походження"] + попереднє["походження_перетворення"]
    for запис in походження:
        назва = запис["файл"]
        if назва.startswith("colour/"):
            шлях = Path(бібліотека.__file__).parent / назва.removeprefix("colour/")
        else:
            шлях = ОСНОВА.ВХІД.parent / назва
            if not шлях.is_file():
                шлях = ОСНОВА.ДЖЕРЕЛА / назва
        if ОСНОВА.походження([(назва, шлях)])[0] != запис:
            raise ValueError(f"Застаріле походження: {назва}")
    return комплекс, походження


def зробити_перетворення(бібліотека):
    """З'єднує попередні нейтральний і хроматичний методи на їхніх областях."""
    хроматичне = ОСНОВА.зробити_перетворення(бібліотека)
    нейтральне = НЕЙТРАЛЬ.зробити_перетворення(бібліотека)

    @lru_cache(maxsize=None)
    def перетворити(H, V, C):
        """Дає точний образ або очікувану відмову без підміни кольором краю."""
        if (not all(math.isfinite(x) for x in (H, V, C))
                or not 1 <= H <= 101 or not 0 <= V <= 10 or C < 0):
            raise ValueError("Поза областю джерела H/V/C")
        if C == 0:
            lab, θLC = нейтральне(V)
            return {"стан": "визначено", "Lab": lab, "θLC": θLC}
        if not СКІНЧЕННІ.визначено_V(V):
            return {"стан": "невизначено", "причина": "V поза овоїдами чинного методу"}
        try:
            lab, θLC = хроматичне(H, V, C)
        except (AssertionError, ValueError) as помилка:
            return {"стан": "невизначено", "причина": "renotation або непридатний XYZ",
                    "відмова": str(помилка)}
        return {"стан": "визначено", "Lab": lab, "θLC": θLC}

    return перетворити


def координати(ребро, параметр):
    """Читає скінченну точку повного інтервалу або відкритого променя ребра."""
    a, b = map(ЗШИВАННЯ.число, ребро["інтервал"])
    if not math.isfinite(параметр) or not a <= параметр <= b:
        raise ValueError("Поза параметричною областю ребра")
    точка = list(ребро["фіксовані"])
    точка.insert("HVC".index(ребро["вісь"]), параметр)
    return tuple(точка)


def читати_ребро(перетворити, ребро, параметр):
    """Повертає точку спільної часткової кривої без інтерполяції свідків."""
    точка = координати(ребро, параметр)
    return {"HVC": точка, **перетворити(*точка)}


def читати_край(перетворити, комплекс, грань, посилання, параметр):
    """Дає спільний образ краю грані й знак обходу в координаті ребра.

Параметр завжди є вихідною H, V або C; знак задає напрямок обходу,
а не інший спосіб округлення або інтерполяції суміжною гранню.
"""
    if (not 0 <= грань < len(комплекс["контури"])
            or посилання not in комплекс["контури"][грань]):
        raise ValueError("Ребро не належить орієнтованому краю грані")
    номер, знак = ЗШИВАННЯ.розпакувати(посилання)
    return {"ребро": номер, "орієнтація": знак,
            **читати_ребро(перетворити, комплекс["ребра"][номер], параметр)}


def ключ_вершини(точка):
    """Склеює H лише на нейтралі; різні V та додатні C не ототожнює."""
    H, V, C = ЗШИВАННЯ.канонічна_точка(точка)
    return (None if C == 0 else H), V, C


def параметри_проб(ребро):
    """Дає свідки, які не задають меж області та не обрізають промінь C."""
    a, b = map(ЗШИВАННЯ.число, ребро["інтервал"])
    if math.isinf(b):
        return [a, a + 1, a + 16, a + 1024]
    значення = {a, (a + b) / 2, b}
    if ребро["вісь"] == "V":
        значення.update(x for x in (0.5, 0.9995, 1, 9, 9.5, 9.9995) if a <= x <= b)
    return sorted(значення)


def породити():
    """Породжує спільні часткові криві, вершини та зв'язки всіх граней."""
    бібліотека = ОСНОВА.залежності()
    комплекс, попереднє = звірити_джерела(бібліотека)
    перетворити = зробити_перетворення(бібліотека)
    вершини, індекси, відповідність = [], {}, []
    for номер, точка in enumerate(комплекс["вершини"]):
        ключ = ключ_вершини(точка)
        if ключ not in індекси:
            індекси[ключ] = len(вершини)
            вершини.append({"ключ": ключ, "джерельні_вершини": [],
                            "образ": перетворити(*точка)})
        індекс = індекси[ключ]
        вершини[індекс]["джерельні_вершини"].append(номер)
        відповідність.append(індекс)
    ребра, стани = [], Counter()
    for номер, ребро in enumerate(комплекс["ребра"]):
        свідки = [читати_ребро(перетворити, ребро, t) for t in параметри_проб(ребро)]
        стани.update(x["стан"] for x in свідки)
        ребра.append({"ребро": номер, "параметр": ребро["вісь"],
                      "межі": ребро["інтервал"],
                      "замкненість": [True, ребро["інтервал"][1] != "+inf"],
                      "виродження_H": ребро["вісь"] == "H" and ребро["фіксовані"][1] == 0,
                      "вершини": [None if i is None else відповідність[i]
                                   for i in ребро["вершини"]], "свідки": свідки})
    походження = ОСНОВА.походження([
        (Path(__file__).name, __file__),
        (ЗШИВАННЯ.ВИХІД.name, ЗШИВАННЯ.ВИХІД),
        (ПОПЕРЕДНІЙ.ВИХІД.name, ПОПЕРЕДНІЙ.ВИХІД),
    ])
    return {"формат": 1, "версії": ОСНОВА.ВЕРСІЇ,
            "статус": "Точні спільні часткові криві; не зшита оболонка Lab",
            "метод": "читати_ребро(зробити_перетворення(Colour), джерельне ребро, параметр)",
            "область": "Повний інтервал джерела; образ рівно при стан=визначено; +inf не точка",
            "апроксимація": "Відсутня; свідки не інтерполюються, неперервність не доведено",
            "походження": походження,
            "походження_перетворення": попереднє,
            "підсумок": {"ребер": len(ребра), "контурів": len(комплекс["контури"]),
                         "джерельних_вершин": len(відповідність), "вершин": len(вершини),
                         "вироджених_H": sum(x["виродження_H"] for x in ребра),
                         "променів": sum(not x["замкненість"][1] for x in ребра),
                         "свідків": sum(стани.values()), "стани_свідків": dict(стани)},
            "вершини": вершини, "вершини_джерела": відповідність, "ребра": ребра,
            "контури": комплекс["контури"], "оболонки_джерела": комплекс["оболонки"]}


def серіалізувати(вихід):
    """Пише стабільний компактний JSON із канонічними числами попередніх методів."""
    return json.dumps(ОСНОВА.округлити(вихід), ensure_ascii=False,
                      allow_nan=False, separators=(",", ":")) + "\n"


def головна():
    """Записує або звіряє відтворюваний вихід спільних ребер."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--записати", action="store_true")
    парсер.add_argument("--вихід", type=Path, default=ВИХІД)
    аргументи = парсер.parse_args()
    вихід = породити()
    текст = серіалізувати(вихід)
    if аргументи.записати:
        аргументи.вихід.write_text(текст, encoding="utf-8", newline="\n")
    elif not аргументи.вихід.exists() or аргументи.вихід.read_text(encoding="utf-8") != текст:
        парсер.exit(1, "Артефакт відсутній або відрізняється від виходу методу\n")
    print(json.dumps(вихід["підсумок"], ensure_ascii=False))


if __name__ == "__main__":
    головна()
