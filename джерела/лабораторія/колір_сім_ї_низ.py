"""Переносить нижні C-грані всередині першого овоїда renotation.

Основна область V>=1 апроксимується попереднім методом Lab; вузька
смуга округлення V<1 читає точний метод. Решта нижньої частини явно
невизначена. Це лабораторний вихід, не визначення сімей продукту.
"""
import argparse
import importlib.util
import inspect
import itertools
import json
import math
from pathlib import Path


ШЛЯХ = Path(__file__).with_name("колір_сім_ї_кінці.py")
СПЕЦИФІКАЦІЯ = importlib.util.spec_from_file_location("кінці", ШЛЯХ)
ПОПЕРЕДНІЙ = importlib.util.module_from_spec(СПЕЦИФІКАЦІЯ)
СПЕЦИФІКАЦІЯ.loader.exec_module(ПОПЕРЕДНІЙ)
ОСНОВА = ПОПЕРЕДНІЙ.ОСНОВА
ВХІД = ОСНОВА.ВХІД
ВИХІД = Path(__file__).with_suffix(".json")


def обрано(грань):
    """Обирає нижні C-грані між нейтраллю та першим табличним овоїдом C=2."""
    return (грань["вісь"] == "C" and 0 < грань["координата"] < 2
            and грань["інтервали"][1][0] == 0
            and 1 < грань["інтервали"][1][1] < 10)


def визначено(V):
    """Читає правило округлення чинного рушія після канонічного запису V.

    Позначення попереднього методу має 12 значущих цифр. За V<1
    хроматична гілка працює лише коли is_integer округлює V до 1;
    інакше вона потребує відсутнього овоїда V=0. Межу не затискаємо.
    """
    from colour.utilities import is_integer
    if not math.isfinite(V) or not 0 < V < 10:
        return False
    V = float(f"{V:.12g}")
    return V >= 1 or (bool(is_integer(V)) and round(V) == 1)


def зробити_перетворення(бібліотека):
    """Повторно використовує хроматичний метод з явною нижньою областю."""
    точне = ОСНОВА.зробити_перетворення(бібліотека)

    def перетворити(H, V, C):
        """Відмовляє поза першим овоїдом або нижньою областю до обчислень."""
        if not all(math.isfinite(x) for x in (H, V, C)):
            raise ValueError("Непридатна координата нижньої грані")
        if not 1 <= H <= 101 or not 0 < C < 2 or not визначено(V):
            raise ValueError("Поза областю нижньої C-грані")
        return точне(H, V, C)

    return перетворити


def перетворити_грань(перетворити, грань, H, V):
    """Читає точний образ точки повної вихідної грані, включно зі смугою V<1."""
    if not обрано(грань):
        raise ValueError("Інший клас грані")
    (H0, H1), (V0, V1) = грань["інтервали"]
    if not H0 <= H <= H1 or not V0 <= V <= V1:
        raise ValueError("Поза вихідною гранню")
    return перетворити(H, V, грань["координата"])


def звірити_попереднє(бібліотека, вхід):
    """Перевіряє транзитивне походження та повний облік кінцевих V-граней."""
    раніше, _ = ПОПЕРЕДНІЙ.звірити_попереднє(бібліотека, вхід)
    кінці = json.loads(ПОПЕРЕДНІЙ.ВИХІД.read_text(encoding="utf-8"))
    номери = [x["грань"] for x in кінці["грані"]]
    очікувані = {i for i, грань in enumerate(вхід["межі"])
                 if грань["вісь"] == "V" and грань["координата"] in (0, 10)}
    if len(set(номери)) != len(номери) or set(номери) != очікувані:
        raise ValueError("Інший клас попередніх V-граней")
    if кінці["раніше"] != раніше:
        raise ValueError("Неузгоджений попередній облік")
    всі = раніше + номери + [x["грань"] for x in кінці["відкладені"]]
    if sorted(всі) != list(range(len(вхід["межі"]))):
        raise ValueError("Пропуск або дубль у попередньому обліку")
    for запис in кінці["грані"]:
        if запис["джерело"] != вхід["межі"][запис["грань"]]:
            raise ValueError("Інше джерело кінцевої грані")
    for запис in кінці["походження"] + кінці["походження_перетворення"]:
        назва = запис["файл"]
        if назва.startswith("colour/"):
            шлях = Path(бібліотека.__file__).parent / назва.removeprefix("colour/")
        else:
            шлях = ВХІД.parent / назва
            if not шлях.is_file():
                шлях = ОСНОВА.ДЖЕРЕЛА / назва
        if ОСНОВА.походження([(назва, шлях)])[0] != запис:
            raise ValueError(f"Застаріле походження: {назва}")
    return sorted(раніше + номери), кінці


def обмежити_xy(грань):
    """Обмежує весь образ диском усередині фізичного трикутника xy.

    Лінійна інтерполяція лежить у диску; радіальна має радіус не більший
    за радіуси кінців. C<2 масштабує радіус від білої точки, а інтерполяція
    V за Y є опуклою. Перевіряємо всі вузли H і потрібні цілі V, не вибірку.
    """
    from colour.notation.munsell import (CCS_ILLUMINANT_MUNSELL,
                                        xyY_from_renotation)
    білий = tuple(float(x) for x in CCS_ILLUMINANT_MUNSELL)
    відстань = min(білий[0], білий[1], (1 - sum(білий)) / math.sqrt(2))
    V1 = math.ceil(грань["інтервали"][1][1])
    радіуси = [math.dist(xyY_from_renotation([H, V, 2, код])[:2], білий)
               for V in range(1, V1 + 1) for код in range(1, 11)
               for H in (2.5, 5, 7.5, 10)]
    радіус = max(радіуси) * грань["координата"] / 2
    if радіус >= відстань:
        raise ValueError("Диск не доводить придатність усієї xy-області")
    return {"вузлів_C2": len(радіуси), "білий_xy": білий,
            "радіус": радіус, "відстань_до_краю_xy": відстань,
            "запас_xy": відстань - радіус}


def породити():
    """Породжує основні ділянки та повне часткове відображення нижніх граней."""
    бібліотека = ОСНОВА.залежності()
    from colour.constants import THRESHOLD_INTEGER
    from colour.utilities import common
    from colour.constants import common as сталі
    перетворити = зробити_перетворення(бібліотека)
    вхід = json.loads(ВХІД.read_text(encoding="utf-8"))
    раніше, кінці = звірити_попереднє(бібліотека, вхід)
    артефакт = {
        "формат": 1, "версії": ОСНОВА.ВЕРСІЇ,
        "походження": ОСНОВА.походження([
            (ВХІД.name, ВХІД), (Path(__file__).name, __file__),
            (ШЛЯХ.name, ШЛЯХ), (ПОПЕРЕДНІЙ.ВИХІД.name, ПОПЕРЕДНІЙ.ВИХІД),
            ("colour/utilities/common.py", inspect.getfile(common)),
            ("colour/constants/common.py", inspect.getfile(сталі))]),
        "походження_перетворення": кінці["походження"] + кінці["походження_перетворення"],
        "статус": "Лабораторне часткове відображення; не оболонка й не вхід продукту",
        "джерело_методу": "https://colour.readthedocs.io/en/v0.4.6/_modules/colour/notation/munsell.html",
        "цілі_похибки": ОСНОВА.РЕЄСТР["похибка"]["val"],
        "подання": "HV і вузли як у методі C-граней; V<1: точний перетворити_грань, без сітки та без підміни V",
        "поріг_цілого_Colour": float(THRESHOLD_INTEGER),
        "предикат_нижньої_смуги": "V12=float(format(V,'.12g')); is_integer(V12) and round(V12)==1",
        "раніше": раніше, "грані": [], "відкладені": [],
    }
    for номер, грань in enumerate(вхід["межі"]):
        if номер in раніше:
            continue
        if not обрано(грань):
            артефакт["відкладені"].append({
                "грань": номер, "причина": "Наступний клас: C>=2, верхній V або необмежений C"})
            continue
        H, (_, V1) = грань["інтервали"]
        ділянки = []
        for межі in itertools.product(ОСНОВА.поділити(H, [2.5 * i for i in range(41)]),
                                     ОСНОВА.поділити([1, V1], range(1, 10))):
            ділянки.extend(ОСНОВА.породити_ділянки(
                перетворити, грань["координата"], межі))
        for ділянка in ділянки:
            вимір = ОСНОВА.перевірити_ділянку(
                перетворити, грань["координата"], ділянка["HV"], ділянка["вузли"],
                itertools.product((0.211324865405187, 0.788675134594813), repeat=2))
            if any(x > ціль for x, ціль in zip(вимір, артефакт["цілі_похибки"])):
                raise ValueError(f"Відкладена перевірка грані {номер}: {вимір}")
            ділянка["перевірка"] = вимір
        артефакт["грані"].append({
            "грань": номер, "джерело": грань,
            "область": {"основна_HV": [H, [1, V1]],
                        "нижня_HV": [H, [0, 1]], "нижня_замкненість_V": [True, False],
                        "визначено_внизу": "предикат_нижньої_смуги",
                        "невизначено_внизу": "not предикат_нижньої_смуги"},
            "обмеження_xy": обмежити_xy(грань), "ділянки": ділянки})
        print(f"Грань {номер}: основних ділянок {len(ділянки)}; нижня смуга — точний метод", flush=True)
    return артефакт


def головна():
    """Записує або побайтово відтворює часткові нижні поверхні."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--записати", action="store_true")
    парсер.add_argument("--вихід", type=Path, default=ВИХІД)
    аргументи = парсер.parse_args()
    артефакт = ОСНОВА.округлити(породити())
    текст = json.dumps(артефакт, ensure_ascii=False, allow_nan=False, separators=(",", ":")) + "\n"
    if аргументи.записати:
        аргументи.вихід.write_text(текст, encoding="utf-8", newline="\n")
    elif not аргументи.вихід.exists() or аргументи.вихід.read_text(encoding="utf-8") != текст:
        парсер.exit(1, "Артефакт відсутній або відрізняється від виходу методу\n")
    print(f"Нижніх граней {len(артефакт['грані'])}; раніше {len(артефакт['раніше'])}; відкладено {len(артефакт['відкладені'])}")


if __name__ == "__main__":
    головна()
