"""Зшиває орієнтовані межі сімей спільними ребрами в просторі джерела.

H періодичний; нескінченність C не є вершиною або кришкою. Це комплекс
джерела до виродження нейтралі й обмеження областю renotation, не оболонка
Lab та не доведення, що межі сімей є многовидами.
"""
import argparse
from collections import Counter
import hashlib
import importlib.util
import json
import math
from pathlib import Path


ШЛЯХ = Path(__file__).with_name("колір_сім_ї_межі.py")
СПЕЦИФІКАЦІЯ = importlib.util.spec_from_file_location("межі", ШЛЯХ)
МЕЖІ = importlib.util.module_from_spec(СПЕЦИФІКАЦІЯ)
СПЕЦИФІКАЦІЯ.loader.exec_module(МЕЖІ)
ВХІД = МЕЖІ.ВИХІД
ВИХІД = Path(__file__).with_suffix(".json")


def число(значення):
    """Відновлює відкритий необмежений кінець із формату джерела."""
    return math.inf if значення == "+inf" else значення


def канонічна_точка(точка):
    """Ототожнює тільки періодичні кінці H, не згортаючи нейтральну вісь."""
    початок, кінець = МЕЖІ.РЕЄСТР["область"]["val"][0]
    H, V, C = точка
    return (початок if H == кінець else H), V, C


def краї_грані(грань):
    """Дає орієнтовані краї з нормаллю вздовж додатної осі H/V/C.

    Знак (-1)^осі узгоджує вільні параметри з орієнтацією dH∧dV∧dC.
    Краю на нескінченності немає; його не замінює скінченна стеля.
    """
    вісь = "HVC".index(грань["вісь"])
    інші = [i for i in range(3) if i != вісь]
    інтервали = [tuple(map(число, пара)) for пара in грань["інтервали"]]
    for змінна in range(2):
        фіксована = 1 - змінна
        for бік in range(2):
            координата = інтервали[фіксована][бік]
            if not math.isfinite(координата):
                continue
            точка = [0] * 3
            точка[вісь] = грань["координата"]
            точка[інші[фіксована]] = координата
            знак = (-1) ** (вісь + змінна + бік)
            yield інші[змінна], tuple(точка), інтервали[змінна], знак


def побудувати(вхід):
    """Розбиває всі краї у спільних вузлах і зберігає кожне ребро один раз.

    Глобальні кінці інтервалів дають точне скінченне розбиття всіх часткових
    збігів і Т-стиків. Змінний H лишається інтервалом до канонізації кінців:
    повний оберт не перетворюється на нульову довжину.
    """
    грані = вхід["межі"]
    осі = [set() for _ in range(3)]
    for грань in грані:
        вісь = "HVC".index(грань["вісь"])
        осі[вісь].add(грань["координата"])
        for i, пара in zip((i for i in range(3) if i != вісь), грань["інтервали"]):
            осі[i].update(map(число, пара))
    осі = [sorted(вісь) for вісь in осі]
    використання = []
    всі_ребра = set()
    for грань in грані:
        контур = []
        for вісь, точка, (низ, верх), знак in краї_грані(грань):
            поділ = [x for x in осі[вісь] if низ <= x <= верх]
            for a, b in zip(поділ, поділ[1:]):
                фіксовані = канонічна_точка(точка)
                ключ = вісь, tuple(фіксовані[i] for i in range(3) if i != вісь), a, b
                всі_ребра.add(ключ)
                контур.append((ключ, знак))
        використання.append(контур)
    ключі = sorted(всі_ребра)
    індекси = {ключ: i for i, ключ in enumerate(ключі)}
    вершини = set()
    кінці = []
    for вісь, фіксовані, a, b in ключі:
        пара = []
        for координата in (a, b):
            if math.isinf(координата):
                пара.append(None)
                continue
            точка = list(фіксовані)
            точка.insert(вісь, координата)
            точка = канонічна_точка(точка)
            вершини.add(точка)
            пара.append(точка)
        кінці.append(пара)
    вершини = sorted(вершини)
    номери = {точка: i for i, точка in enumerate(вершини)}
    ребра = [{"вісь": "HVC"[вісь], "фіксовані": list(фіксовані),
              "інтервал": [a, "+inf" if math.isinf(b) else b],
              "вершини": [None if x is None else номери[x] for x in пара],
              "грані": []}
             for (вісь, фіксовані, a, b), пара in zip(ключі, кінці)]
    контури = []
    for i, контур in enumerate(використання):
        контури.append([знак * (індекси[ключ] + 1) for ключ, знак in контур])
        for ключ, знак in контур:
            ребра[індекси[ключ]]["грані"].append(знак * (i + 1))
    оболонки = {код: [] for код in вхід["сім_ї"]}
    for i, грань in enumerate(грані):
        for знак, сім_я in zip((1, -1), грань["сім_ї"]):
            if сім_я is not None:
                оболонки[сім_я].append(знак * (i + 1))
    return {"вершини": [list(x) for x in вершини], "ребра": ребра,
            "контури": контури, "оболонки": оболонки}


def розпакувати(посилання):
    """Читає орієнтований індекс: ±(номер+1), без неоднозначності нуля."""
    return abs(посилання) - 1, 1 if посилання > 0 else -1


def перевірити(комплекс):
    """Відмовляє при незамкненому контурі або нескороченій межі сім'ї."""
    ребра = комплекс["ребра"]
    контури = комплекс["контури"]
    for номер, контур in enumerate(контури):
        залишок = Counter()
        for посилання in контур:
            ребро, знак = розпакувати(посилання)
            for бік, вершина in enumerate(ребра[ребро]["вершини"]):
                if вершина is not None:
                    залишок[вершина] += знак * (-1 if бік == 0 else 1)
        if any(залишок.values()):
            raise ValueError(f"Незамкнений контур грані {номер}")
    для_сімей, особливі = {}, []
    for код, оболонка in комплекс["оболонки"].items():
        залишок, кратність = Counter(), Counter()
        for посилання in оболонка:
            грань, назовні = розпакувати(посилання)
            for край in контури[грань]:
                ребро, знак = розпакувати(край)
                залишок[ребро] += назовні * знак
                кратність[ребро] += 1
        if any(залишок.values()):
            raise ValueError(f"Незамкнена межа сім'ї {код}")
        для_сімей[код] = {"граней": len(оболонка), "ребер": len(кратність),
                          "кратності": dict(sorted(Counter(кратність.values()).items()))}
        особливі.extend({"сім_я": код, "ребро": i, "кратність": n}
                        for i, n in sorted(кратність.items()) if n != 2)
    return {"граней": len(контури), "ребер": len(ребра),
            "вершин": len(комплекс["вершини"]),
            "променів": sum(x["вершини"][1] is None for x in ребра),
            "використань": sum(map(len, контури)), "сім_ї": для_сімей,
            "недвобічні_стики": особливі}


def походження(шляхи):
    """Фіксує SHA-256 текстів LF, незалежно від завершень рядків checkout."""
    return [{"файл": шлях.relative_to(МЕЖІ.ДЖЕРЕЛА).as_posix(),
             "sha256_lf": hashlib.sha256(шлях.read_text(encoding="utf-8").encode()).hexdigest()}
            for шлях in шляхи]


def породити():
    """Звіряє джерело й породжує комплекс без числового перетворення кольору."""
    вхід = json.loads(ВХІД.read_text(encoding="utf-8"))
    if вхід != МЕЖІ.породити():
        raise ValueError("Межі не відповідають чинним джерелам")
    комплекс = побудувати(вхід)
    return {"формат": 1,
            "статус": "Зшивання в H/V/C до вироджень та області renotation; не оболонка Lab",
            "індекси": "вершини від 0; орієнтовані грані й ребра — ±(номер+1)",
            "нескінченність": "+inf — відкритий напрямок, кінцева вершина null; кришки немає",
            "походження": походження([ВХІД, ШЛЯХ, Path(__file__),
                                       МЕЖІ.ТАБЛИЦЯ, МЕЖІ.КЛІТИНКИ]),
            "підсумок": перевірити(комплекс), **комплекс}


def серіалізувати(вихід):
    """Групує записи стабільного JSON, не роздуваючи артефакт тисячами рядків."""
    масиви = ("вершини", "ребра", "контури")
    шапка = {k: v for k, v in вихід.items() if k not in (*масиви, "оболонки")}
    текст = json.dumps(шапка, ensure_ascii=False, allow_nan=False, indent=2)[:-2]
    рядки = [json.dumps(k) + ': ' + json.dumps(v) for k, v in вихід["оболонки"].items()]
    текст += ',\n  "оболонки": {\n    ' + ',\n    '.join(рядки) + '\n  }'
    for ключ in масиви:
        рядки = [json.dumps(x, ensure_ascii=False, allow_nan=False) for x in вихід[ключ]]
        крок = 8 if ключ == "вершини" else 2
        групи = [', '.join(рядки[i:i + крок]) for i in range(0, len(рядки), крок)]
        текст += f',\n  "{ключ}": [\n    ' + ',\n    '.join(групи) + '\n  ]'
    return текст + '\n}\n'


def головна():
    """Записує LF або звіряє канонічний текст LF стандартним Python."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--записати", action="store_true")
    парсер.add_argument("--вихід", type=Path, default=ВИХІД)
    аргументи = парсер.parse_args()
    вихід = породити()
    текст = серіалізувати(вихід)
    if аргументи.записати:
        аргументи.вихід.write_text(текст, encoding="utf-8", newline="\n")
    elif not аргументи.вихід.exists() or аргументи.вихід.read_text(encoding="utf-8") != текст:
        парсер.exit(1, "Артефакт відсутній або відрізняється від виходу методу\n")
    print(json.dumps(вихід["підсумок"], ensure_ascii=False))


if __name__ == "__main__":
    головна()
