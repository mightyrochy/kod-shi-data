def розрізнювальна_здатність(набори, зважувати_площею=False, метрика="oklab"):
    """Скільки реального каталогу ця ціль насправді розрізняє.

    `набори` — список образів, кожен = список речей у форматі outfit.елементи.
    Повертає частку в середній третині рангу. Це і є число, задля якого правило
    або лишається правилом, або знижується до пояснення."""
    середні = []
    for речі in набори:
        E = речі if (речі and isinstance(речі[0], dict) and "lab" in речі[0]) \
            else O.елементи(речі)
        середні.append(середня_близькість(E, зважувати_площею, метрика))
    # МЕТРИКА ПЕРЕДАЄТЬСЯ ДАЛІ. Було: `розкид_набору(середні)` без неї, тобто на
    # `метрика="de00"` підлога шуму бралася з OKLab (0.025 замість 5.0) і будь-який
    # набір визнавався придатним до ранжування. Той самий клас, що й підписи
    # одиниць: параметр є, а до споживача не доїжджає.
    діагноз = розкид_набору(середні, метрика)
    ранги = [ранг_у_наборі(v, середні) for v in середні]
    у_середній = [r for r in ранги if r is not None and 1/3 <= r <= 2/3]
    порахованих = [r for r in ранги if r is not None]
    частка = (len(у_середній) / len(порахованих)) if порахованих else None
    return dict(
        n_образів=len(набори), n_із_кольором=len(порахованих),
        середні_близькості=середні, одиниці=МЕТРИКИ[метрика][1], ранги=ранги,
        розкид=діагноз,
        частка_в_середній_третині=(round(частка, 3) if частка is not None else None),
        вердикт=(None if частка is None else
                 ("НЕ ФІЛЬТР: %.0f%% у середній третині — ціль пропускає майже все. "
                  "Звітувати як пояснення, не як правило; композиторові потрібен член "
                  "на розкид усередині образу" % (частка * 100) if частка > 0.70 else
                  "РОЗДІЛЯЄ: %.0f%% у середній третині — набір розпадається, ціль "
                  "лишається `default`" % (частка * 100))),
        передбачення=ПЕРЕДБАЧЕННЯ,
        не_зроблено="прогін на СИНТЕТИЦІ нічого не валідує: числа мають прийти з "
                    "feed.прогін по живому українському фіду. Доти це порожня форма")


def розрізнювальна_інтенсивності(набори, поріг_голосу=0.30):
    """Скільки комбінацій K-COMP-04 узагалі РОЗРІЗНЯЄ. Не опція — умова прийняття.

    ЧОМУ ЦЯ ФУНКЦІЯ ІСНУЄ, І ЧОМУ ВОНА ЗʼЯВИЛАСЬ ПІЗНІШЕ ЗА САМЕ ПРАВИЛО. Правило
    я перевірив на опрацьованому прикладі корпусу (шавлія+неон → 0.74, шавлія+іржа
    → 0.01) і на цьому зупинився. Приклад підібраний АВТОРОМ ТЕМИ так, щоб різниця
    була максимальна; він доводить, що механізм правильний, і нічого не каже про
    те, чи трапляється така пара в українському масмаркеті.

    ВИМІРЯНО НА КАТАЛОЗІ (діалект Rozetka, `run_outfit.МОДЕЛІ`, 90 комбінацій):
        сила ≥0.30 — 0 комбінацій (0%)
        сила ≥0.05 — 0 комбінацій
        медіана 0.000, МАКСИМУМ 0.000
    Тобто на цьому каталозі правило мовчить ЗАВЖДИ. Причина не в правилі: масмаркет
    тут суцільно приглушений, розрив хроми ніде не підходить навіть до нижньої межі
    0.044. Наслідок для рішення — нульовий: образ, який іде людині, з правилом і без
    нього той самий (перевірено підміною емітента на порожній).

    ЩО ЦЕ ЗНАЧИТЬ ЧЕСНО: K-COMP-04 виконується й лишає слід, але ТРЕТІЙ ЯРУС — «змінює
    хоч одне рішення про річ» — на цьому каталозі НЕ ПРОЙДЕНО. Правило чекає каталогу
    з неоном або з кислотними акцентами; доти воно спляче, а не робоче. Записувати
    його в оживлені на підставі сліду означало б рахувати покриття за якість.
    """
    сили = []
    for речі in набори:
        # «lab у першому елементі» — НЕДОСТАТНЯ ознака готових елементів: сира річ
        # із фіду теж несе `lab`, але не несе `річ`. Перевіряємо саме `річ`, бо
        # це поле, яке додає `елементи()` і яке читає `одна_на_річ`.
        E = речі if (речі and isinstance(речі[0], dict) and "річ" in речі[0]) \
            else O.елементи(речі)
        з = інтенсивність(E)
        сили.append(з[0]["сила_нп"] if з else 0.0)
    n = len(сили) or 1
    голос = sum(1 for s in сили if s >= поріг_голосу)
    return dict(
        n=len(сили), голосів=голос, частка_голосів=round(голос / n, 3),
        медіана=round(sorted(сили)[len(сили) // 2], 3) if сили else None,
        максимум=round(max(сили), 3) if сили else None,
        вердикт=("МОВЧИТЬ НА ЦЬОМУ ПУЛІ: жодна комбінація не дає розриву хроми, "
                 "навіть до нижньої межі. Третій ярус (зміна рішення) не пройдено — "
                 "правило спляче, не робоче" if голос == 0 else
                 "розрізняє %d із %d комбінацій (%.0f%%)" % (голос, n, 100 * голос / n)),
        не_зроблено="пул синтетичний. Число стане чинним лише на живому українському "
                    "фіді: якщо й там 0%, правило треба або знімати з відбору, або "
                    "чекати сегмента каталогу, де воно має вхід")


