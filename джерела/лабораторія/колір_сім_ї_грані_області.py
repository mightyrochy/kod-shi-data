"""Дає область кожної з 234 граней на області renotation клітинками будови Colour.

Грань ділиться на клітинки добутком частин вільних осей: H — смуги тонів
даних і проміжки (лінійні чи радіальні овоїди), V — смуги цілих і проміжки
(лінійність за Y), C — смуги парних і проміжки (лінійність за C). У клітинці
наявність даних стала, а xy — мультиафінна суміш овоїдів за вагами t(V), s(C):
мінімум кожного обмеження XYZ ≥ 0 — у кутах (t, s), уздовж H — доведення
знака з ребер тону. Стан клітинки: «+» визначено повністю, «-» даних нема,
«z» уся клітинка поза XYZ, «x» межа XYZ усередині (не перенесено).
Не оболонка Lab, не вхід продукту.
"""
import argparse
import importlib.util
import json
import math
from pathlib import Path


def завантажити(назва, файл):
    """Читає попередній лабораторний метод із його теки, без пакета."""
    специфікація = importlib.util.spec_from_file_location(назва, Path(__file__).with_name(файл))
    модуль = importlib.util.module_from_spec(специфікація)
    специфікація.loader.exec_module(модуль)
    return модуль


ТОН = завантажити("ребра_тону", "колір_сім_ї_ребра_тону.py")
РЕБРА, ОСНОВА, ЗШИВАННЯ = ТОН.РЕБРА, ТОН.ОСНОВА, ТОН.ЗШИВАННЯ
ВИХІД = Path(__file__).with_suffix(".json")


def основа_C(смуги_C):
    """Проміжки між парними C (відкриті), смуги парних (замкнені), поза 50 — без даних."""
    основа, попередня = [], 0.0
    for c in РЕБРА.ПАРНІ_C[1:]:
        основа += [(попередня, смуги_C[c][0], False, False, "між"),
                   (*смуги_C[c], True, True, "смуга")]
        попередня = смуги_C[c][1]
    return основа + [(попередня, math.inf, False, False, "поза")]


def члени_V(бібліотека, частина):
    """Члени за V: [(вага t-кінця, v)] або None; v=10 у проміжку — сірий."""
    від, до, _, _, (a, b, вид) = частина
    if вид == "смуга":
        k = round((a + b) / 2)
        return None if k in (0, 10) else ([(1.0, k)], None)
    k = math.floor(a)
    if k == 0:
        return None
    Y = lambda V: float(бібліотека.notation.munsell.luminance_ASTMD1535(float(f"{V:.12g}")))
    t = [(Y(x) - Y(k)) / (Y(k + 1) - Y(k)) for x in (від, до)]
    return [(None, k), (None, k + 1)], t


def члени_C(частина):
    """Члени за C: [(None, c)] із вагою s на кутах або None поза даними; c=0 — сірий."""
    від, до, _, _, (a, b, вид) = частина
    if вид == "поза":
        return None
    if вид == "смуга":
        return [(1.0, round((a + b) / 2))], None
    низ = 2 * round(a / 2) if a > 0 else 0
    if a > 0 and низ > a:
        низ -= 2
    return [(None, низ), (None, низ + 2)], [(x - низ) / 2 for x in (від, до)]


def ваги(члени, параметр, кут):
    """Ваги членів на куті клітинки: 1−t і t для проміжку, 1 для смуги."""
    список, межі = члени
    if межі is None:
        return список
    t = межі[кут]
    return [(1 - t, список[0][1]), (t, список[1][1])]


class Грань:
    """Кеш членів овоїдів за частинами H однієї грані."""

    def __init__(self, бібліотека):
        self.бібліотека = бібліотека
        self.сірий = [float(x) for x in бібліотека.notation.munsell.CCS_ILLUMINANT_MUNSELL]
        self.кеш = {}

    def член(self, H_частина, v, c):
        """Член (v, c) на частині H: стала, лінійна чи радіальна модель або None."""
        if v == 10 or c == 0:
            return {"вид": "стала", "xy": self.сірий}
        ключ = (H_частина[:2], H_частина[4][2] if len(H_частина) > 4 else "точка", v, c)
        if ключ not in self.кеш:
            від, до = H_частина[0], H_частина[1]
            if len(H_частина) == 2 or H_частина[4][2] == "смуга":
                точка = ТОН.овоїд(self.бібліотека, (від + до) / 2, v, c)
                self.кеш[ключ] = точка and {"вид": "стала", "xy": list(точка)}
            else:
                a, b = H_частина[4][:2]
                self.кеш[ключ] = ТОН.модель_члена(self.бібліотека, v, c, a, b)
        return self.кеш[ключ]


def стан_клітинки(грань, H_частина, частина_V, частина_C):
    """«+», «-», «z» чи «x» для клітинки: дані членів і доведений знак XYZ у кутах.

    Обмеження мультиафінне за (t, s): його максимум і мінімум на клітинці — у
    кутах, тож усі кути з доведеним «+» — уся клітинка, усі з «−» хоч для
    одного обмеження — уся клітинка поза XYZ («z»), інакше межа всередині («x»).
    """
    кV, кC = члени_V(грань.бібліотека, частина_V), члени_C(частина_C)
    if кV is None or кC is None:
        return "-"
    знаки = {назва: set() for назва in ТОН.ОБМЕЖЕННЯ}
    for кут_V in (0, 1):
        for кут_C in (0, 1):
            модель = []
            for wv, v in ваги(кV, "t", кут_V):
                for wc, c in ваги(кC, "s", кут_C):
                    член = грань.член(H_частина, v, c)
                    if член is None:
                        return "-"
                    модель.append((wv * wc, член))
            for назва in ТОН.ОБМЕЖЕННЯ:
                форма = ТОН.обмеження(модель, назва)
                if not форма[2] and форма[1] == 0:
                    знаки[назва].add(1 if форма[0] > ТОН.ЗАПАС else
                                     -1 if форма[0] < -ТОН.ЗАПАС else 0)
                    continue
                a = H_частина[4][0]
                знаки[назва] |= {знак for *_, знак in ТОН.доведені_знаки(
                    форма, H_частина[0] - a, H_частина[1] - a)[0]}
    if any(x == {-1} for x in знаки.values()):
        return "z"
    return "+" if all(x == {1} for x in знаки.values()) else "x"


def частини_осі(вісь, низ, верх, основи):
    """Частини вільної чи фіксованої осі, обрізані [низ, верх]."""
    return РЕБРА.частини(низ, верх, основи[вісь](низ, верх))


def область_грані(бібліотека, смуги, запис):
    """Частини осей і рядки станів клітинок однієї грані."""
    фіксована = запис["вісь"]
    вільні = [x for x in "HVC" if x != фіксована]
    інтервали = [tuple(map(ЗШИВАННЯ.число, пара)) for пара in запис["інтервали"]]
    x0 = запис["координата"]
    основи = {"H": lambda н, в: ТОН.основа_H(ТОН.смуги_тону(бібліотека, н, в), н, в),
              "V": lambda н, в: РЕБРА.основа_V(смуги[0]),
              "C": lambda н, в: основа_C(смуги[1])}
    if фіксована == "C" and x0 == 0:
        return {"нейтраль": True, "осі": вільні, "частини": [], "стани": []}
    # Фіксований H читає точку овоїда прямо; V і C — свою частину будови.
    фікс = [None] if фіксована == "H" else частини_осі(фіксована, x0, x0, основи)
    if len(фікс) != 1:
        raise ValueError(f"Фіксована координата {фіксована}={x0} у кількох частинах")
    частини = [частини_осі(вісь, *інтервал, основи) for вісь, інтервал in zip(вільні, інтервали)]
    грань = Грань(бібліотека)
    стани = []
    for p in частини[0]:
        рядок = ""
        for q in частини[1]:
            за_віссю = dict(zip(вільні, (p, q)))
            за_віссю[фіксована] = фікс[0]
            H = за_віссю["H"]
            if фіксована == "H":
                H = (x0, x0)
            рядок += стан_клітинки(грань, H, за_віссю["V"], за_віссю["C"])
        стани.append(рядок)
    return {"осі": вільні, "фіксована": [фіксована, x0],
            "частини": [[[від, до, зв, зд, вид] for від, до, зв, зд, (_, _, вид) in осі]
                        for осі in частини],
            "стани": стани}


def породити():
    """Звіряє ребра тону повним породженням і ділить кожну грань на клітинки."""
    бібліотека = ОСНОВА.залежності()
    if ТОН.серіалізувати(ТОН.породити()) != ТОН.ВИХІД.read_text(encoding="utf-8"):
        raise ValueError("Ребра тону не відповідають чинному методу")
    межі = json.loads(ОСНОВА.ВХІД.read_text(encoding="utf-8"))["межі"]
    смуги = РЕБРА.смуги(бібліотека)
    грані = [dict(грань=i, **область_грані(бібліотека, смуги, x)) for i, x in enumerate(межі)]
    клітинки = {}
    for x in грані:
        for рядок in x["стани"]:
            for стан in рядок:
                клітинки[стан] = клітинки.get(стан, 0) + 1
    def вид(x):
        стани = "".join(x["стани"])
        if x.get("нейтраль"):
            return "нейтраль"
        return "повна" if set(стани) == {"+"} else "порожня" if set(стани) <= {"-", "z"} else (
            "межа XYZ" if "x" in стани else "часткова")
    return {
        "формат": 1, "версії": ОСНОВА.ВЕРСІЇ,
        "походження": ОСНОВА.походження([
            (Path(__file__).name, __file__), (Path(ТОН.__file__).name, ТОН.__file__),
            (ТОН.ВИХІД.name, ТОН.ВИХІД), (ОСНОВА.ВХІД.name, ОСНОВА.ВХІД)]),
        "статус": "Області граней клітинками будови Colour; «x» — межа XYZ не перенесена; не оболонка Lab",
        "клітинка": "добуток частин двох вільних осей [від, до, замкнено_від, замкнено_до, вид];"
                    " рядок станів — частина першої осі, символ — другої",
        "стани": {"+": "визначено всю клітинку", "-": "даних renotation нема",
                  "z": "уся клітинка поза XYZ ≥ 0",
                  "x": "межа XYZ усередині, не перенесено"},
        "підсумок": {"граней": len(грані), "клітинки": клітинки,
                     "грані": {в: sum(вид(x) == в for x in грані)
                               for в in ("повна", "часткова", "порожня", "межа XYZ", "нейтраль")}},
        "грані": грані,
    }


def серіалізувати(вихід):
    """Пише стабільний JSON: по запису грані в рядку, межі частин точними float."""
    шапка = {k: v for k, v in вихід.items() if k != "грані"}
    текст = json.dumps(шапка, ensure_ascii=False, allow_nan=False, indent=1)[:-2]
    рядки = [json.dumps(x, ensure_ascii=False).replace("Infinity", '"+inf"') for x in вихід["грані"]]
    return текст + ',\n "грані": [\n  ' + ',\n  '.join(рядки) + '\n ]\n}\n'


def головна():
    """Записує LF або побайтово звіряє збережений вихід методу."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--записати", action="store_true")
    парсер.add_argument("--вихід", type=Path, default=ВИХІД)
    аргументи = парсер.parse_args()
    вихід = породити()
    текст = серіалізувати(вихід)
    if аргументи.записати:
        аргументи.вихід.write_text(текст, encoding="utf-8", newline="\n")
    elif not аргументи.вихід.exists() or аргументи.вихід.read_text(encoding="utf-8") != текст:
        парсер.exit(1, "Артефакт відсутній або відрізняється від виходу методу\n")
    print(json.dumps(вихід["підсумок"], ensure_ascii=False))


if __name__ == "__main__":
    головна()
