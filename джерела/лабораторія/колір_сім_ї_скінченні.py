"""Задає точні часткові відображення скінченних H/C-граней біля V=0/10.

Параметри пробігають повні вихідні прямокутники. Область читає чинний
renotation та перевірка XYZ попереднього методу; невизначена точка
не має координат. Це процедурні поверхні, не трикутна оболонка продукту.
"""
import argparse
import importlib.util
import json
import math
from pathlib import Path


ШЛЯХ = Path(__file__).with_name("колір_сім_ї_низ.py")
СПЕЦИФІКАЦІЯ = importlib.util.spec_from_file_location("низ", ШЛЯХ)
ПОПЕРЕДНІЙ = importlib.util.module_from_spec(СПЕЦИФІКАЦІЯ)
СПЕЦИФІКАЦІЯ.loader.exec_module(ПОПЕРЕДНІЙ)
ОСНОВА = ПОПЕРЕДНІЙ.ОСНОВА
ВХІД = ОСНОВА.ВХІД
ВИХІД = Path(__file__).with_suffix(".json")


def обрано(грань):
    """Обирає весь скінченний H/C-клас біля кінців, крім вже перенесеного низу."""
    if грань["вісь"] not in ("H", "C"):
        return False
    if грань["вісь"] == "C" and грань["координата"] <= 0:
        return False
    if not all(isinstance(x, (int, float)) and math.isfinite(x)
               for пара in грань["інтервали"] for x in пара):
        return False
    V = грань["інтервали"][0 if грань["вісь"] == "H" else 1]
    return (V[0] == 0 or V[1] == 10) and not ПОПЕРЕДНІЙ.обрано(грань)


def звірити_попереднє(бібліотека, вхід):
    """Звіряє попередні класи, повний облік та транзитивне походження низу."""
    раніше, _ = ПОПЕРЕДНІЙ.звірити_попереднє(бібліотека, вхід)
    низ = json.loads(ПОПЕРЕДНІЙ.ВИХІД.read_text(encoding="utf-8"))
    номери = [x["грань"] for x in низ["грані"]]
    очікувані = {i for i, g in enumerate(вхід["межі"]) if ПОПЕРЕДНІЙ.обрано(g)}
    if len(номери) != len(set(номери)) or set(номери) != очікувані:
        raise ValueError("Інший клас попередніх нижніх граней")
    if низ["раніше"] != раніше:
        raise ValueError("Неузгоджений попередній облік низу")
    всі = раніше + номери + [x["грань"] for x in низ["відкладені"]]
    if sorted(всі) != list(range(len(вхід["межі"]))):
        raise ValueError("Пропуск або дубль у попередньому обліку низу")
    for запис in низ["грані"]:
        if запис["джерело"] != вхід["межі"][запис["грань"]]:
            raise ValueError("Інше джерело нижньої грані")
    for запис in низ["походження"] + низ["походження_перетворення"]:
        назва = запис["файл"]
        if назва.startswith("colour/"):
            шлях = Path(бібліотека.__file__).parent / назва.removeprefix("colour/")
        else:
            шлях = ВХІД.parent / назва
            if not шлях.is_file():
                шлях = ОСНОВА.ДЖЕРЕЛА / назва
        if ОСНОВА.походження([(назва, шлях)])[0] != запис:
            raise ValueError(f"Застаріле походження: {назва}")
    return sorted(раніше + номери), низ


def координати(грань, u, v):
    """Розгортає параметри повної H/C-грані без затискання її країв."""
    if not обрано(грань):
        raise ValueError("Інший клас грані")
    if not all(math.isfinite(x) for x in (u, v)):
        raise ValueError("Непридатний параметр грані")
    if not all(a <= x <= b for x, (a, b) in zip((u, v), грань["інтервали"])):
        raise ValueError("Поза вихідною гранню")
    if грань["вісь"] == "H":
        return грань["координата"], u, v
    return u, v, грань["координата"]


def визначено_V(V):
    """Читає гілку V чинного методу після його канонічного форматування.

    Нижній цілий овоїд має бути 1…9. Верхній V=10 викликається як
    нейтраль лише у нецілій гілці; округлення самого V до 10 потребує
    відсутнього хроматичного овоїда. Це не обмеження максимальної C.
    """
    from colour.utilities import is_integer
    if not math.isfinite(V) or not 0 < V < 10:
        return False
    V = float(f"{V:.12g}")
    return 1 <= (round(V) if is_integer(V) else math.floor(V)) <= 9


def перетворити_грань(перетворити, грань, u, v):
    """Повертає точний образ або явну невизначеність точки вихідної грані.

    Лише очікувані відмови renotation/XYZ стають невизначеним образом;
    помилки виклику, іншого класу чи параметрів поширюються викликачу.
    Стелю C не використовуємо як доказ фізичної придатності XYZ.
    """
    H, V, C = координати(грань, u, v)
    запис = {"HVC": [H, V, C]}
    if not визначено_V(V):
        return dict(запис, стан="невизначено", причина="V поза овоїдами чинного методу")
    try:
        lab, θLC = перетворити(H, V, C)
    except (AssertionError, ValueError) as помилка:
        return dict(запис, стан="невизначено", причина="renotation або непридатний XYZ",
                    відмова=str(помилка))
    return dict(запис, стан="визначено", Lab=lab, θLC=θLC)


def параметри_проб(грань):
    """Дає відтворювані свідки країв, середини й обох смуг округлення V."""
    V_вісь = 0 if грань["вісь"] == "H" else 1
    пари = []
    for вісь, (a, b) in enumerate(грань["інтервали"]):
        значення = {a, (a + b) / 2, b}
        if вісь == V_вісь:
            значення.update(x for x in (0.5, 0.999, 0.9995, 1, 9, 9.5,
                                        9.9985, 9.999, 9.9995) if a <= x <= b)
        пари.append(sorted(значення))
    return [(u, v) for u in пари[0] for v in пари[1]]


def породити():
    """Породжує повні процедурні області, їхні свідки й облік усіх граней."""
    бібліотека = ОСНОВА.залежності()
    перетворити = ОСНОВА.зробити_перетворення(бібліотека)
    вхід = json.loads(ВХІД.read_text(encoding="utf-8"))
    раніше, низ = звірити_попереднє(бібліотека, вхід)
    артефакт = {
        "формат": 1, "версії": ОСНОВА.ВЕРСІЇ,
        "походження": ОСНОВА.походження([
            (Path(__file__).name, __file__), (ШЛЯХ.name, ШЛЯХ),
            (ПОПЕРЕДНІЙ.ВИХІД.name, ПОПЕРЕДНІЙ.ВИХІД)]),
        "походження_перетворення": низ["походження"] + низ["походження_перетворення"],
        "статус": "Точне процедурне часткове відображення; не сітка, не оболонка й не вхід продукту",
        "джерело_методу": "https://colour.readthedocs.io/en/v0.4.6/_modules/colour/notation/munsell.html",
        "метод": "перетворити_грань(ОСНОВА.зробити_перетворення(Colour), джерело, u, v)",
        "область": "Повний замкнений прямокутник джерела; образ існує рівно при стан=визначено",
        "невизначено": "Доповнення визначеної області; координат Lab/θLC немає",
        "апроксимація": "Немає; свідки не інтерполюються й не задають меж області",
        "раніше": раніше, "грані": [], "відкладені": [],
    }
    for номер, грань in enumerate(вхід["межі"]):
        if номер in раніше:
            continue
        if not обрано(грань):
            артефакт["відкладені"].append({"грань": номер, "причина": "Необмежений C"})
            continue
        свідки = [перетворити_грань(перетворити, грань, u, v)
                  for u, v in параметри_проб(грань)]
        артефакт["грані"].append({
            "грань": номер, "джерело": грань,
            "параметри": ["V", "C"] if грань["вісь"] == "H" else ["H", "V"],
            "межі": грань["інтервали"], "замкненість": [[True, True], [True, True]],
            "свідки": свідки})
        прийнято = sum(x["стан"] == "визначено" for x in свідки)
        print(f"Грань {номер}: визначено {прийнято}, невизначено {len(свідки) - прийнято}", flush=True)
    return артефакт


def головна():
    """Записує або побайтово відтворює точні процедурні скінченні поверхні."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--записати", action="store_true")
    парсер.add_argument("--вихід", type=Path, default=ВИХІД)
    аргументи = парсер.parse_args()
    текст = json.dumps(ОСНОВА.округлити(породити()), ensure_ascii=False,
                       allow_nan=False, separators=(",", ":")) + "\n"
    if аргументи.записати:
        аргументи.вихід.write_text(текст, encoding="utf-8", newline="\n")
    elif not аргументи.вихід.exists() or аргументи.вихід.read_text(encoding="utf-8") != текст:
        парсер.exit(1, "Артефакт відсутній або відрізняється від виходу методу\n")


if __name__ == "__main__":
    головна()
