# Colour 0.4.6 xy_from_renotation_ovoid: attest 2 <= chroma <= 50, парна хрома.
ПАРНІ_C = [2 * k for k in range(26)]
ЦІЛІ_V = range(11)
ЛІНІЙНІСТЬ = 1e-12


def зробити_вимір(бібліотека):
    """Дає xyY чинного renotation або None, коли метод не має даних."""
    def xyY(H, V, C):
        if not СКІНЧЕННІ.визначено_V(V):
            return None
        try:
            return tuple(float(x) for x in бібліотека.notation.munsell_colour_to_xyY(
                ОСНОВА.позначення(H, V, C)))
        except (AssertionError, ValueError):
            return None
    return xyY


def смуга_V(бібліотека, V):
    """Читає гілку цілого V Colour після канонічного запису 12 цифр."""
    return bool(бібліотека.utilities.is_integer(float(f"{V:.12g}")))


def межа(предикат, всередині, назовні):
    """Дає останній float, де предикат істинний, бісекцією самого предиката."""
    if not предикат(всередині) or предикат(назовні):
        raise ValueError(f"Неочікувана смуга біля {всередині}")
    while True:
        середина = (всередині + назовні) / 2
        if середина in (всередині, назовні):
            return всередині
        if предикат(середина):
            всередині = середина
        else:
            назовні = середина


def смуги(бібліотека):
    """Точні смуги однакових даних Colour після запису 12 значущих цифр.

    V: is_integer з порогом 1e-3 читає один овоїд; C: запис, рівний парній
    хромі, читає один овоїд (chroma % 2 == 0), інакше — два сусідні.
    """
    V = {k: (межа(lambda x: смуга_V(бібліотека, x), k - 0.0009, k - 0.0011) if k > 0 else 0.0,
             межа(lambda x: смуга_V(бібліотека, x), k + 0.0009, k + 0.0011) if k < 10 else 10.0)
         for k in ЦІЛІ_V}
    C = {c: (межа(lambda x: float(f"{x:.12g}") == c, c, c * (1 - 1e-9)),
             межа(lambda x: float(f"{x:.12g}") == c, c, c * (1 + 1e-9)))
         for c in ПАРНІ_C if c > 0}
    return V, C


def частини(низ, верх, основа):
    """Обрізає основні частини Colour замкненим ребром [низ, верх].

    Основа — (від, до, замкнено_від, замкнено_до, вид), що разом покривають
    вісь без перекриття. Кінець ребра всередині частини стає замкненим.
    """
    результат = []
    for a, b, ca, cb, вид in основа:
        p, q = max(a, низ), min(b, верх)
        зв = ca if p == a else True
        зд = cb if q == b else True
        if p < q or (p == q and зв and зд):
            результат.append((p, q, зв, зд, (a, b, вид)))
    return результат


def лінійна(вимір, точки):
    """Відновлює xy = α + β·s з двох внутрішніх точок і перевіряє третьою."""
    (s1, p1), (s2, p2), (s3, p3) = точки
    β = [(p2[i] - p1[i]) / (s2 - s1) for i in range(2)]
    α = [p1[i] - β[i] * s1 for i in range(2)]
    if any(abs(α[i] + β[i] * s3 - p3[i]) > ЛІНІЙНІСТЬ for i in range(2)):
        raise ValueError(f"xy не лінійний у частині: {вимір}")
    return α, β


def допустиме(α, β, від, до, зв, зд):
    """Перетинає частину з y>0, x≥0, x+y≤1 (X, Y, Z ≥ 0 при Y>0)."""
    обмеження = [(α[1], β[1], False), (α[0], β[0], True),
                 (1 - α[0] - α[1], -β[0] - β[1], True)]
    межі = ["частина", "частина"]
    for a, b, замкнене in обмеження:
        if b == 0:
            if a < 0 or (a == 0 and not замкнене):
                return None
            continue
        r = -a / b
        if b > 0 and (r > від or (r == від and not замкнене)):
            від, зв, межі[0] = r, замкнене, "XYZ"
        elif b < 0 and (r < до or (r == до and not замкнене)):
            до, зд, межі[1] = r, замкнене, "XYZ"
    if від > до or (від == до and not (зв and зд)):
        return None
    return від, до, зв, зд, межі


def область_C(вимір, H, V, низ, верх, смуги_C):
    """Точна хроматична область ребра вздовж C за кусково-лінійною хромою.

    У відкритому (2k−2, 2k) Colour читає ті самі овоїди, xy лінійний за C;
    у парній C — один овоїд; за C>50 attest відмовляє. C=0 — нейтраль.
    """
    основа, попередня = [], 0.0
    for c in ПАРНІ_C[1:]:
        основа += [(попередня, смуги_C[c][0], False, False, "між"),
                   (*смуги_C[c], True, True, "точка")]
        попередня = смуги_C[c][1]
    основа.append((попередня, math.inf, False, False, "поза"))
    результат = []
    for від, до, зв, зд, (a, b, вид) in частини(низ, верх, основа):
        if вид == "поза":
            if вимір(H, V, a + 1) is not None or вимір(H, V, 1e6) is not None:
                raise ValueError("Colour дав хрому понад 50")
            continue
        if вид == "точка":
            точка = вимір(H, V, (a + b) / 2)
            шматок = точка and допустиме(точка[:2], [0.0, 0.0], від, до, зв, зд)
        else:
            точки = [(a + (b - a) * t, вимір(H, V, a + (b - a) * t)) for t in (0.25, 0.5, 0.75)]
            if any(p is None for _, p in точки):
                if any(p is not None for _, p in точки):
                    raise ValueError("Непостійні дані Colour у частині C")
                continue
            шматок = допустиме(*лінійна((H, V, a, b), точки), від, до, зв, зд)
        if шматок:
            результат.append(шматок)
    return злити(результат, низ, верх, "нейтраль" if низ == 0 else "край ребра")


def основа_V(смуги):
    """Смуги цілих V (замкнені) і проміжки між ними (відкриті) на [0, 10]."""
    основа = []
    for k in ЦІЛІ_V:
        основа.append((смуги[k][0], смуги[k][1], True, True, "смуга"))
        if k < 10:
            основа.append((смуги[k][1], смуги[k + 1][0], False, False, "між"))
    return основа


def область_V(бібліотека, вимір, H, C, низ, верх, смуги):
    """Точна область ребра вздовж V: смуги цілих V та лінійність xy за Y.

    У смузі цілого k Colour читає один овоїд, xy сталий; між смугами —
    лінійна інтерполяція за Y ASTM D1535. Межі Y повертає бісекція V.
    """
    Y = lambda V: float(бібліотека.notation.munsell.luminance_ASTMD1535(V)) / 100
    результат = []
    for від, до, зв, зд, (a, b, вид) in частини(низ, верх, основа_V(смуги)):
        if вид == "смуга":
            точка = вимір(H, (a + b) / 2, C)
            шматок = точка and допустиме(точка[:2], [0.0, 0.0], від, до, зв, зд)
            if шматок:
                результат.append(шматок)
            continue
        точки = [(Y(v), вимір(H, v, C)) for v in (a + (b - a) * t for t in (0.25, 0.5, 0.75))]
        if any(p is None for _, p in точки):
            if any(p is not None for _, p in точки):
                raise ValueError("Непостійні дані Colour у частині V")
            continue
        шматок = допустиме(*лінійна((H, C, a, b), точки), Y(від), Y(до), зв, зд)
        if шматок:
            yв, yд, зв2, зд2, межі = шматок
            результат.append((обернути_Y(Y, yв, від, до), обернути_Y(Y, yд, від, до),
                              зв2, зд2, межі))
    return злити(результат, низ, верх, "край ребра")


def обернути_Y(Y, ціль, від, до):
    """Обертає зростаючу Y(V) ASTM D1535 бісекцією в межах частини."""
    if Y(від) >= ціль:
        return від
    if Y(до) <= ціль:
        return до
    while True:
        середина = (від + до) / 2
        if середина in (від, до):
            return до
        if Y(середина) < ціль:
            від = середина
        else:
            до = середина


def злити(шматки, низ, верх, край_низу):
    """Зливає суміжні визначені шматки в максимальні інтервали з причинами меж."""
    злиті = []
    for від, до, зв, зд, межі in sorted(шматки, key=lambda x: (x[0], x[1])):
        if злиті and злиті[-1]["до"] == від and (злиті[-1]["замкнено"][1] or зв):
            злиті[-1].update(до=до, замкнено=[злиті[-1]["замкнено"][0], зд])
            злиті[-1]["межі"][1] = межі[1]
            continue
        злиті.append({"від": від, "до": до, "замкнено": [зв, зд], "межі": list(межі)})
    for інтервал in злиті:
        if інтервал["від"] == низ:
            інтервал["межі"][0] = край_низу
        if інтервал["до"] == верх:
            інтервал["межі"][1] = "край ребра"
        for бік in range(2):
            if інтервал["межі"][бік] == "частина":
                інтервал["межі"][бік] = "дані renotation"
    return злиті


def вершина(перетворити, нейтраль, точка):
    """Дає образ вершини: нейтральна точка, хроматичний колір чи невизначеність."""
    H, V, C = точка
    if C == 0:
        lab, θLC = нейтраль(V)
        return {"HVC": точка, "стан": "нейтраль", "V": V, "Lab": lab, "θLC": θLC}
    if V in (0, 10):
        return {"HVC": точка, "стан": "невизначено", "причина": "кінець V без хроматичного овоїда"}
    try:
        lab, θLC = перетворити(H, V, C)
    except (AssertionError, ValueError) as помилка:
        return {"HVC": точка, "стан": "невизначено", "причина": "renotation або непридатний XYZ",
                "відмова": str(помилка)}
    return {"HVC": точка, "стан": "визначено", "Lab": lab, "θLC": θLC}


def ребро(бібліотека, вимір, смуги, запис, нейтральні):
    """Класифікує спільне ребро й дає його образ або точну область."""
    вісь, фіксовані = запис["вісь"], запис["фіксовані"]
    низ, верх = ЗШИВАННЯ.число(запис["інтервал"][0]), ЗШИВАННЯ.число(запис["інтервал"][1])
    if вісь == "H":
        V, C = фіксовані
        if C == 0:
            return {"клас": "нейтральна точка", "нейтраль": нейтральні[V]}
        if V in (0, 10):
            return {"клас": "кінець V", "область": []}
        return {"клас": "відкладено", "причина": "радіальна інтерполяція тону"}
    if вісь == "V":
        H, C = фіксовані
        if C == 0:
            return {"клас": "нейтральний відрізок", "V": [низ, верх],
                    "нейтраль": [нейтральні[низ], нейтральні[верх]]}
        return {"клас": "V", "область": область_V(бібліотека, вимір, H, C, низ, верх, смуги[0])}
    H, V = фіксовані
    if V in (0, 10):
        запис = {"клас": "кінець V", "область": []}
        if низ == 0:
            запис["нейтраль"] = нейтральні[V]
        return запис
    запис = {"клас": "C", "область": область_C(вимір, H, V, низ, верх, смуги[1])}
    if низ == 0:
        запис["нейтраль"] = нейтральні[V]
    return запис


def звірити_фактор(комплекс, нейтральні):
    """Звіряє, що згортання C=0 лишає контури замкненими, а нейтральну грань — нулем."""
    ребра, вершини = комплекс["ребра"], комплекс["вершини"]

    def образ(номер):
        запис = ребра[номер]
        if запис["вісь"] == "H" and запис["фіксовані"][1] == 0:
            return None
        return [None if x is None else (нейтральні[вершини[x][1]] if вершини[x][2] == 0
                                        else f"в{x}") for x in запис["вершини"]]

    нульові = []
    for номер, контур in enumerate(комплекс["контури"]):
        залишок, ланцюг = {}, {}
        for посилання in контур:
            індекс, знак = ЗШИВАННЯ.розпакувати(посилання)
            кінці = образ(індекс)
            if кінці is None:
                continue
            ключ = ("н", *кінці) if all(isinstance(x, int) for x in кінці) else ("р", індекс)
            ланцюг[ключ] = ланцюг.get(ключ, 0) + знак
            for бік, точка in enumerate(кінці):
                if точка is not None:
                    залишок[точка] = залишок.get(точка, 0) + знак * (1 if бік else -1)
        if any(залишок.values()):
            raise ValueError(f"Контур {номер} розімкнено згортанням нейтралі")
        if not any(ланцюг.values()):
            нульові.append(номер)
    return нульові


def породити():
    """Звіряє зшивання й облік граней, потім переносить вершини й ребра."""
    бібліотека = ОСНОВА.залежності()
    перетворити = ОСНОВА.зробити_перетворення(бібліотека)
    нейтраль = НЕЙТРАЛЬ.зробити_перетворення(бібліотека)
    вимір = зробити_вимір(бібліотека)
    комплекс = json.loads(ВХІД.read_text(encoding="utf-8"))
    if ЗШИВАННЯ.серіалізувати(ЗШИВАННЯ.породити()) != ВХІД.read_text(encoding="utf-8"):
        raise ValueError("Зшивання не відповідає чинному методу")
    межі = json.loads(ОСНОВА.ВХІД.read_text(encoding="utf-8"))
    облік, попереднє = НЕОБМЕЖЕНІ.звірити_попереднє(бібліотека, межі)
    облік = sorted(облік + [x["грань"] for x in json.loads(
        НЕОБМЕЖЕНІ.ВИХІД.read_text(encoding="utf-8"))["грані"]])
    if облік != list(range(len(межі["межі"]))):
        raise ValueError("Попередній облік граней неповний")
    смуги_даних = смуги(бібліотека)
    нейтральні_V = sorted({x[1] for x in комплекс["вершини"] if x[2] == 0})
    нейтральні = {V: i for i, V in enumerate(нейтральні_V)}
    вершини = [вершина(перетворити, нейтраль, x) for x in комплекс["вершини"]]
    ребра = [ребро(бібліотека, вимір, смуги_даних, x, нейтральні)
             for x in комплекс["ребра"]]
    нульові = звірити_фактор(комплекс, нейтральні)
    класи = {}
    for запис in ребра:
        класи[запис["клас"]] = класи.get(запис["клас"], 0) + 1
    return {
        "формат": 1, "версії": ОСНОВА.ВЕРСІЇ,
        "походження": ОСНОВА.походження([
            (Path(__file__).name, __file__), (ЗШИВАННЯ.ШЛЯХ.name, ЗШИВАННЯ.ШЛЯХ),
            (Path(ЗШИВАННЯ.__file__).name, ЗШИВАННЯ.__file__), (ВХІД.name, ВХІД),
            (НЕОБМЕЖЕНІ.ВИХІД.name, НЕОБМЕЖЕНІ.ВИХІД)]),
        "походження_перетворення": попереднє["походження"] + попереднє["походження_перетворення"],
        "статус": "Ребра зшивання на області renotation і нейтралі; H-ребра відкладено; не оболонка Lab",
        "джерело_методу": попереднє["джерело_методу"],
        "нейтраль": "C=0: вершини з тим самим V — одна точка; H-ребро — точка, V-ребро — відрізок кривої",
        "область": "Об'єднання інтервалів параметра ребра; замкнено — [від, до]; поза ними образу немає",
        "межі_області": "край ребра | нейтраль (відкритий кінець C>0) | дані renotation | XYZ",
        "смуги_V": {str(k): list(v) for k, v in смуги_даних[0].items()},
        "смуги_C": {str(k): list(v) for k, v in смуги_даних[1].items()},
        "підсумок": {"вершин": len(вершини), "ребер": len(ребра), "класи": класи,
                     "нейтральних_точок": len(нейтральні_V),
                     "вершини": {стан: sum(x["стан"] == стан for x in вершини)
                                 for стан in ("нейтраль", "визначено", "невизначено")},
                     "вироджені_контури": нульові},
        "нейтральні_V": нейтральні_V,
        "вершини": вершини,
        "ребра": [dict(ребро=i, **x) for i, x in enumerate(ребра)],
    }


def округлити_образи(значення):
    """Округлює лише координати образів; межі області й смуг лишає точними float."""
    if isinstance(значення, dict):
        return {k: ОСНОВА.округлити(v) if k in ("Lab", "θLC") else округлити_образи(v)
                for k, v in значення.items()}
    if isinstance(значення, list):
        return [округлити_образи(x) for x in значення]
    return значення


def серіалізувати(вихід):
    """Пише стабільний JSON: по запису вершини чи ребра в рядку."""
    шапка = {k: v for k, v in вихід.items() if k not in ("вершини", "ребра")}
    текст = json.dumps(округлити_образи(шапка), ensure_ascii=False, allow_nan=False, indent=1)[:-2]
    for ключ in ("вершини", "ребра"):
        рядки = [json.dumps(округлити_образи(x), ensure_ascii=False, allow_nan=False)
                 for x in вихід[ключ]]
        текст += f',\n "{ключ}": [\n  ' + ',\n  '.join(рядки) + '\n ]'
    return текст + '\n}\n'


def головна():
    """Записує LF або побайтово звіряє збережений вихід методу."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--записати", action="store_true")
    парсер.add_argument("--вихід", type=Path, default=ВИХІД)
    аргументи = парсер.parse_args()
    вихід = породити()
    текст = серіалізувати(вихід)
    if аргументи.записати:
        аргументи.вихід.write_text(текст, encoding="utf-8", newline="\n")
    elif not аргументи.вихід.exists() or аргументи.вихід.read_text(encoding="utf-8") != текст:
        парсер.exit(1, "Артефакт відсутній або відрізняється від виходу методу\n")
    print(json.dumps(вихід["підсумок"], ensure_ascii=False))


if __name__ == "__main__":
    головна()
