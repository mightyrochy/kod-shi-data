"""Переносить спільні ребра зшивання на область renotation та нейтральну вісь.

C=0 згортає H: вершини з тим самим V стають однією нейтральною точкою,
ребро вздовж H — точкою, ребро вздовж V — відрізком нейтральної кривої.
Хроматичні ребра вздовж C і V дістають точну область чинного методу з
кусково-лінійної будови Colour 0.4.6; ребра вздовж H відкладено:
радіальна інтерполяція тону не лінійна. Не оболонка Lab, не вхід продукту.
"""
