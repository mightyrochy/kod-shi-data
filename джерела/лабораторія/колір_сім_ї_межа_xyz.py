"""Дає явну криву межі XYZ ≥ 0 у кожній клітинці «x» областей граней на renotation.

У клітинці «x» обмеження g (y, x чи 1−x−y) мультиафінне за вагами t(V), s(C),
а за H — модель ребер тону. Одна вісь клітинки — параметр p (H, а при сталому
H — V через вагу t), друга — вага w (C через s, при сталому C — V через t):
g = (1−w)·G0(p) + w·G1(p) — афінна за w форма, її корінь w*(p) = G0/(G0 − G1)
і є кривою межі. Знаки G на двох краях клітинки за w доведено поділом проміжку
p (як у ребрах тону), корені уточнено бісекцією моделі: на кожній частині p
обмеження або виконано для всієї клітинки, або ніде, або з одного боку кривої.
Не оболонка Lab, не вхід продукту.
"""
