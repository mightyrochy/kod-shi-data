def частини_грані(бібліотека, смуги, запис):
    """Частини вільних осей і фіксованої осі — тим самим розбиттям, що області граней."""
    фіксована = запис["вісь"]
    вільні = [x for x in "HVC" if x != фіксована]
    інтервали = [tuple(map(ЗШИВАННЯ.число, пара)) for пара in запис["інтервали"]]
    x0 = запис["координата"]
    основи = {"H": lambda н, в: ТОН.основа_H(ТОН.смуги_тону(бібліотека, н, в), н, в),
              "V": lambda н, в: РЕБРА.основа_V(смуги[0]),
              "C": lambda н, в: ГРАНІ.основа_C(смуги[1])}
    фікс = [None] if фіксована == "H" else ГРАНІ.частини_осі(фіксована, x0, x0, основи)
    if len(фікс) != 1:
        raise ValueError(f"Фіксована координата {фіксована}={x0} у кількох частинах")
    return вільні, фікс[0], [ГРАНІ.частини_осі(вісь, *інтервал, основи)
                             for вісь, інтервал in zip(вільні, інтервали)]


def вага_V(бібліотека, k, V):
    """Вага t верхнього овоїда між цілими k і k+1 — як у члени_V, за Y ASTM D1535."""
    Y = lambda x: float(бібліотека.notation.munsell.luminance_ASTMD1535(float(f"{x:.12g}")))
    return (Y(V) - Y(k)) / (Y(k + 1) - Y(k))


def члени_осі(бібліотека, вісь, частина):
    """(члени [v чи c], [вага від, вага до] або None для смуги, нижній член)."""
    if вісь == "V":
        члени, ваги = ГРАНІ.члени_V(бібліотека, частина)
    else:
        члени, ваги = ГРАНІ.члени_C(частина)
    return [x for _, x in члени], ваги


def скласти(форми):
    """Лінійна комбінація форм [(вага, (A, B, радіальні))] — та сама форма."""
    A = sum(в * ф[0] for в, ф in форми)
    B = sum(в * ф[1] for в, ф in форми)
    радіальні = [(в * w, a, b, ρ, φ) for в, ф in форми if в for w, a, b, ρ, φ in ф[2]]
    return A, B, радіальні


def форми_клітинки(грань, осі, частини):
    """Форми обмежень на кінцях ваги w як функції змінної параметра p.

    Дає (вісь p, зміщення змінної, вісь w, ваги w клітинки або None,
    {обмеження: [G0, G1] або [G]}). Змінна p — u = H − a для H, t для V.
    """
    бібліотека = грань.бібліотека
    H, частина_V, частина_C = частини["H"], частини["V"], частини["C"]
    члени_V, ваги_V = члени_осі(бібліотека, "V", частина_V)
    члени_C, ваги_C = члени_осі(бібліотека, "C", частина_C)
    вісь_p = "H" if "H" in осі else "V"
    вісь_w = [x for x in осі if x != вісь_p][0]
    зміщення = H[4][0] if вісь_p == "H" and len(H) > 2 and H[4][2] == "між" else 0.0

    def ваги_осі(члени, ваги, вільна):
        """[(вага, член)] для фіксованої чи смуги; для вільної — None (ставить кінець)."""
        if ваги is None:
            return [(1.0, члени[0])]
        if вільна:
            return None
        t = ваги[0]
        return [(1 - t, члени[0]), (t, члени[1])]

    def кінець(члени, ваги, e):
        """Вага кінця e ∈ {0, 1} вільної осі w: увесь член e."""
        return [(1.0, члени[0])] if ваги is None else [(1.0, члени[e])]

    def обмеження_моделі(назва, вага_V_список, вага_C_список):
        """Форма обмеження суміші членів за H-частиною."""
        модель = []
        for wv, v in вага_V_список:
            for wc, c in вага_C_список:
                член = грань.член(H, v, c)
                if член is None:
                    raise ValueError(f"Член без даних у клітинці «x»: {(H, v, c)}")
                модель.append((wv * wc, член))
        return ТОН.обмеження(модель, назва)

    w_ваги = ваги_C if вісь_w == "C" else ваги_V
    кінці = (0,) if w_ваги is None else (0, 1)
    форми = {}
    for назва in ТОН.ОБМЕЖЕННЯ:
        список = []
        for e in кінці:
            if вісь_p == "H":
                wV = кінець(члени_V, ваги_V, e) if вісь_w == "V" else ваги_осі(члени_V, ваги_V, False)
                wC = кінець(члени_C, ваги_C, e) if вісь_w == "C" else ваги_осі(члени_C, ваги_C, False)
                список.append(обмеження_моделі(назва, wV, wC))
            else:
                # Сталий H: члени — точки, форма за t — (1−t)·K(v0) + t·K(v1).
                wC = кінець(члени_C, ваги_C, e)
                K = [обмеження_моделі(назва, [(1.0, v)], wC)[0] for v in члени_V]
                список.append((K[0], 0.0, []) if ваги_V is None else (K[0], K[1] - K[0], []))
        форми[назва] = список
    return вісь_p, зміщення, вісь_w, w_ваги, форми


def змінна(бібліотека, вісь_p, зміщення, частина_p):
    """Відображення координати p у змінну форми та її межі на частині."""
    if вісь_p == "H":
        перетворення = lambda x: x - зміщення
    else:
        ваги = ГРАНІ.члени_V(бібліотека, частина_p)[1]
        k = math.floor(частина_p[4][0])
        перетворення = (lambda x: 0.0) if ваги is None else (lambda x: вага_V(бібліотека, k, x))
    return перетворення


def знаки_на_частині(форма, перетворення, від, до):
    """[(від, до, знак)] у координаті p зі сталим доведеним знаком форми, корені — бісекцією."""
    низ, верх = перетворення(від), перетворення(до)
    проміжки, _ = ТОН.доведені_знаки(форма, низ, верх)
    значення = lambda x: ТОН.g(форма, перетворення(x))[0]
    послідовність = []
    for p, q, знак in проміжки:
        if знак != "корінь":
            послідовність.append(знак)
            continue
        # Корінь у координаті: бісекція моделі між кінцями дужки (монотонність доведено).
        a, b = координата(перетворення, від, до, p), координата(перетворення, від, до, q)
        ga = значення(a)
        while True:
            m = (a + b) / 2
            if m in (a, b):
                break
            if (значення(m) > 0) == (ga > 0):
                a = m
            else:
                b = m
        r = float(f"{b:.{ЦИФРИ}g}")
        if not від < r < до:
            raise ValueError(f"Корінь форми поза частиною: {r} у [{від}, {до}]")
        послідовність += [1 if ga > 0 else -1, ("корінь", r), -1 if ga > 0 else 1]
    частини, початок, поточний = [], від, None
    for елемент in послідовність:
        if isinstance(елемент, tuple):
            частини.append((початок, елемент[1], поточний))
            початок, поточний = елемент[1], None
        elif поточний is None:
            поточний = елемент
        elif елемент != поточний:
            raise ValueError(f"Зміна знака без кореня на [{від}, {до}]")
    частини.append((початок, до, поточний))
    return частини


def координата(перетворення, від, до, змінна_p):
    """Координата p, чия змінна — задана (H — зсув; V — бісекція монотонної t)."""
    if перетворення(від) == змінна_p:
        return від
    if перетворення(до) == змінна_p:
        return до
    a, b = від, до
    while True:
        m = (a + b) / 2
        if m in (a, b):
            return a
        if перетворення(m) < змінна_p:
            a = m
        else:
            b = m


def поєднати(списки, від, до):
    """Спільне подрібнення кількох [(від, до, знак)] — [(від, до, [знаки])]."""
    точки = sorted({від, до} | {x for с in списки for p, q, _ in с for x in (p, q)})
    результат = []
    for p, q in zip(точки, точки[1:]):
        m = (p + q) / 2
        результат.append((p, q, [next(з for a, b, з in с if a <= m <= b) for с in списки]))
    return результат


def стан_обмеження(знаки):
    """«+» усі w, «-» жодне, «≤» w від нижнього краю до кривої, «≥» від кривої до верхнього."""
    if len(знаки) == 1 or знаки[0] == знаки[1]:
        return "+" if знаки[0] > 0 else "-"
    return "≤" if знаки[0] > 0 else "≥"


def крива_клітинки(грань, осі, частини, клітинка):
    """Опис клітинки «x»: форми обмежень і частини p зі станом кожного обмеження."""
    вісь_p, зміщення, вісь_w, w_ваги, форми = форми_клітинки(грань, осі, частини)
    частина_p = частини[вісь_p]
    від, до = частина_p[0], частина_p[1]
    перетворення = змінна(грань.бібліотека, вісь_p, зміщення, частина_p)
    обмеження, списки = {}, []
    for назва, список in форми.items():
        краї = (список if w_ваги is None else
                [скласти([(1 - w, список[0]), (w, список[1])]) for w in w_ваги])
        знаки = [знаки_на_частині(форма, перетворення, від, до) for форма in краї]
        стани = [(p, q, стан_обмеження(з)) for p, q, з in поєднати(знаки, від, до)]
        if [x[2] for x in стани] == ["+"]:
            continue
        обмеження[назва] = {"G": [форма_запис(ф) for ф in список], "частини": злити(стани)}
        списки.append(обмеження[назва]["частини"])
    разом = []
    for p, q, стани in поєднати([[(a, b, s) for a, b, s in с] for с in списки], від, до):
        криві = [f"{s} {н}" for н, s in zip(обмеження, стани) if s in ("≤", "≥")]
        if "-" in стани:
            разом.append((p, q, "-"))
        elif not криві:
            разом.append((p, q, "+"))
        elif len(криві) == 1:
            разом.append((p, q, криві[0]))
        else:
            raise ValueError(f"Дві криві в одній частині клітинки {клітинка}: {криві}")
    разом = злити(разом)
    if [x[2] for x in разом] == ["+"] or all(x[2] == "-" for x in разом):
        raise ValueError(f"Клітинка «x» {клітинка} без межі всередині")
    p_вісь = {"вісь": вісь_p, "від": від, "до": до, "замкнено": [частина_p[2], частина_p[3]],
              "змінна": "u = H − від_частини" if вісь_p == "H" else "t(V)",
              "від_частини": зміщення if вісь_p == "H" else math.floor(частина_p[4][0])}
    if вісь_p == "V" and ГРАНІ.члени_V(грань.бібліотека, частина_p)[1] is None:
        p_вісь["змінна"] = "смуга цілого V"
    частина_w = частини[вісь_w]
    w_вісь = {"вісь": вісь_w, "від": частина_w[0], "до": частина_w[1],
              "замкнено": [частина_w[2], частина_w[3]], "ваги": w_ваги,
              "члени": члени_осі(грань.бібліотека, вісь_w, частина_w)[0]}
    return {"p": p_вісь, "w": w_вісь, "обмеження": обмеження, "частини": [list(x) for x in разом]}


def злити(частини):
    """Зливає сусідні частини з тим самим станом."""
    результат = []
    for p, q, s in частини:
        if результат and результат[-1][2] == s and результат[-1][1] == p:
            результат[-1] = (результат[-1][0], q, s)
        else:
            результат.append((p, q, s))
    return результат


def форма_запис(форма):
    """Форма для виходу: A, B і радіальні [вага, a, b, ρ0, ρ1, φ0, φ1]."""
    A, B, радіальні = форма
    return {"A": A, "B": B, "радіальні": [[w, a, b, *ρ, *φ] for w, a, b, ρ, φ in радіальні]}


def форма_з_запису(запис):
    """Зворотне до форма_запис: форма для ТОН.g."""
    return (запис["A"], запис["B"],
            [(w, a, b, (ρ0, ρ1), (φ0, φ1)) for w, a, b, ρ0, ρ1, φ0, φ1 in запис["радіальні"]])


def вага_кривої(запис, змінна_p):
    """w*(p) = G0/(G0 − G1) обмеження в змінній p."""
    G0, G1 = (ТОН.g(форма_з_запису(x), змінна_p)[0] for x in запис["G"])
    return G0 / (G0 - G1)


def породити():
    """Звіряє області граней повним породженням і описує межу кожної клітинки «x»."""
    бібліотека = ОСНОВА.залежності()
    if ГРАНІ.серіалізувати(ГРАНІ.породити()) != ГРАНІ.ВИХІД.read_text(encoding="utf-8"):
        raise ValueError("Області граней не відповідають чинному методу")
    області = json.loads(ГРАНІ.ВИХІД.read_text(encoding="utf-8"))["грані"]
    межі = json.loads(ОСНОВА.ВХІД.read_text(encoding="utf-8"))["межі"]
    смуги = РЕБРА.смуги(бібліотека)
    клітинки = []
    for область in області:
        if "x" not in "".join(область["стани"]):
            continue
        запис = межі[область["грань"]]
        вільні, фікс, частини = частини_грані(бібліотека, смуги, запис)
        збережені = [[[від, до, зв, зд, вид] for від, до, зв, зд, (_, _, вид) in осі] for осі in частини]
        if json.loads(json.dumps(збережені).replace("Infinity", '"+inf"')) != область["частини"]:
            raise ValueError(f"Частини грані {область['грань']} не збігаються з областями граней")
        грань = ГРАНІ.Грань(бібліотека)
        for i, рядок in enumerate(область["стани"]):
            for j, стан in enumerate(рядок):
                if стан != "x":
                    continue
                за_віссю = dict(zip(вільні, (частини[0][i], частини[1][j])))
                фіксована, x0 = запис["вісь"], запис["координата"]
                за_віссю[фіксована] = (x0, x0) if фіксована == "H" else фікс
                клітинка = (область["грань"], i, j)
                клітинки.append(dict(грань=клітинка[0], клітинка=[i, j],
                                     **крива_клітинки(грань, вільні, за_віссю, клітинка)))
    стани = {}
    for x in клітинки:
        for *_, s in x["частини"]:
            стани[s] = стани.get(s, 0) + 1
    return {
        "формат": 1, "версії": ОСНОВА.ВЕРСІЇ,
        "походження": ОСНОВА.походження([
            (Path(__file__).name, __file__), (Path(ГРАНІ.__file__).name, ГРАНІ.__file__),
            (ГРАНІ.ВИХІД.name, ГРАНІ.ВИХІД), (ОСНОВА.ВХІД.name, ОСНОВА.ВХІД)]),
        "статус": "Явна крива межі XYZ у клітинках «x» областей граней; не оболонка Lab",
        "крива": "g = (1−w)·G0(p) + w·G1(p); межа w*(p) = G0/(G0 − G1); G — форма ребер тону"
                 " A + B·p + Σ вага·ρ(p)·(a·cos φ(p) + b·sin φ(p)), ρ, φ = [стала, нахил];"
                 " p — змінна осі p (u = H − від_частини або t(V)), w — вага осі w (s(C) або t(V))",
        "стани": {"+": "обмеження виконано для всіх w клітинки", "-": "ні для якого w",
                  "≤ g": "виконано від нижнього краю w до кривої g",
                  "≥ g": "виконано від кривої g до верхнього краю w"},
        "підсумок": {"клітинок": len(клітинки), "граней": len({x["грань"] for x in клітинки}),
                     "обмеження": {н: sum(н in x["обмеження"] for x in клітинки) for н in ТОН.ОБМЕЖЕННЯ},
                     "частини": стани},
        "клітинки": клітинки,
    }


def округлити(значення, цифри=None):
    """Коефіцієнти форм і ваги — 12 значущими цифрами; межі частин лишає записом виходу."""
    if isinstance(значення, float) and цифри:
        return float(f"{значення:.{цифри}g}")
    if isinstance(значення, dict):
        return {k: округлити(v, ЦИФРИ if k in ("G", "ваги") else цифри) for k, v in значення.items()}
    if isinstance(значення, list):
        return [округлити(x, цифри) for x in значення]
    return значення


def серіалізувати(вихід):
    """Пише стабільний JSON: по клітинці в рядку."""
    шапка = {k: v for k, v in вихід.items() if k != "клітинки"}
    текст = json.dumps(шапка, ensure_ascii=False, allow_nan=False, indent=1)[:-2]
    рядки = [json.dumps(округлити(x), ensure_ascii=False).replace("Infinity", '"+inf"')
             for x in вихід["клітинки"]]
    return текст + ',\n "клітинки": [\n  ' + ',\n  '.join(рядки) + '\n ]\n}\n'


def головна():
    """Записує LF або побайтово звіряє збережений вихід методу."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--записати", action="store_true")
    парсер.add_argument("--вихід", type=Path, default=ВИХІД)
    аргументи = парсер.parse_args()
    вихід = породити()
    текст = серіалізувати(вихід)
    if аргументи.записати:
        аргументи.вихід.write_text(текст, encoding="utf-8", newline="\n")
    elif not аргументи.вихід.exists() or аргументи.вихід.read_text(encoding="utf-8") != текст:
        парсер.exit(1, "Артефакт відсутній або відрізняється від виходу методу\n")
    print(json.dumps(вихід["підсумок"], ensure_ascii=False))


if __name__ == "__main__":
    головна()
