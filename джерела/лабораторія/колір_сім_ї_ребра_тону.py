def округлити(значення):
    """Округлює лише коефіцієнти моделі; межі області й частин лишає точними float."""
    if isinstance(значення, dict):
        return {k: ОСНОВА.округлити(v) if k in ("α", "β", "ρ", "φ", "xy", "сірий", "вага")
                else округлити(v) for k, v in значення.items()}
    if isinstance(значення, list):
        return [округлити(x) for x in значення]
    return значення


def серіалізувати(вихід):
    """Пише стабільний JSON: по запису ребра в рядку."""
    шапка = {k: v for k, v in вихід.items() if k != "ребра"}
    текст = json.dumps(шапка, ensure_ascii=False, allow_nan=False, indent=1)[:-2]
    рядки = [json.dumps(округлити(x), ensure_ascii=False, allow_nan=False) for x in вихід["ребра"]]
    return текст + ',\n "ребра": [\n  ' + ',\n  '.join(рядки) + '\n ]\n}\n'


def головна():
    """Записує LF або побайтово звіряє збережений вихід методу."""
    парсер = argparse.ArgumentParser(description=__doc__)
