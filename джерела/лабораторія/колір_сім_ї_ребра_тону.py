"""Дає точну область 243 ребер уздовж H на області renotation, з доведенням знака XYZ.

Уздовж H при сталих V і C xy Colour 0.4.6 — стала суміш до чотирьох точок
овоїдів (сусідні цілі V, сусідні парні C) і сірого. Біля тонів даних
(|тон − 2.5k| < 10⁻³ після запису 12 цифр) кожна точка — запис даних;
між смугами точка лінійна за H або радіальна: ρ і φ лінійні за H, xy — дуга
спіралі. Наявність даних у кожній частині читається викликом Colour;
XYZ ≥ 0 (y>0, x≥0, x+y≤1) доводиться поділом проміжку з межами першої й
другої похідних моделі, корені уточнює бісекція прямого методу.
Не оболонка Lab і не області граней, не вхід продукту.
"""
import argparse
import importlib.util
import json
import math
from pathlib import Path


def завантажити(назва, файл):
    """Читає попередній лабораторний метод із його теки, без пакета."""
    специфікація = importlib.util.spec_from_file_location(назва, Path(__file__).with_name(файл))
    модуль = importlib.util.module_from_spec(специфікація)
    специфікація.loader.exec_module(модуль)
    return модуль


РЕБРА = завантажити("ребра", "колір_сім_ї_ребра.py")
ЗШИВАННЯ, ОСНОВА, СКІНЧЕННІ = РЕБРА.ЗШИВАННЯ, РЕБРА.ОСНОВА, РЕБРА.СКІНЧЕННІ
ВХІД = РЕБРА.ВИХІД
ВИХІД = Path(__file__).with_suffix(".json")
ТОНИ_ДАНИХ = (0.0, 2.5, 5.0, 7.5, 10.0)
# Проби моделі в частині: спіраль розгортається послідовно, крок ≤ 1/16 частини.
ПРОБИ = 17
МОДЕЛЬ = 1e-12
# Запас знака доведення: похибка float моделі й розбіжність із записом 12 цифр.
ЗАПАС = 1e-9
ГЛИБИНА = 60


def тон(бібліотека, H):
    """Нормалізований (тон, код) Colour для ASTM H після запису 12 цифр."""
    специфікація = бібліотека.notation.munsell.munsell_colour_to_munsell_specification(
        ОСНОВА.позначення(H, 5, 2))
    return float(специфікація[0]), int(специфікація[3])


def смуга_тону(бібліотека, H):
    """Гілка даних xy_from_renotation_ovoid: |тон − 2.5k| < THRESHOLD_INTEGER."""
    поріг = бібліотека.constants.THRESHOLD_INTEGER
    return any(abs(тон(бібліотека, H)[0] - t) < поріг for t in ТОНИ_ДАНИХ)


def смуги_тону(бібліотека, низ, верх):
    """Точні смуги тонів даних 2.5k, що перетинають [низ, верх], — останні float предиката.

    Тони даних в області H 1…101 — 2.5…100; смуга кожного лежить усередині області.
    Смуга 10k ділиться: до 10k запис «10X», після — «0.00…Y» з тоном 0 наступної
    родини, гілка даних Colour читає їх різними записами.
    """
    результат = []
    for k in range(1, 41):
        H = 2.5 * k
        ліво = РЕБРА.межа(lambda x: смуга_тону(бібліотека, x), H, H - 0.0011)
        право = РЕБРА.межа(lambda x: смуга_тону(бібліотека, x), H, H + 0.0011)
        if право < низ or ліво > верх:
            continue
        if k % 4:
            результат.append((ліво, право))
        else:
            результат += [(ліво, H), (math.nextafter(H, math.inf), право)]
    return результат


def основа_H(смуги, низ, верх):
    """Смуги тонів даних (замкнені) і проміжки між ними (відкриті) навколо [низ, верх]."""
    основа, попередня, замкнено = [], низ, True
    for ліво, право in смуги:
        if math.nextafter(попередня, math.inf) < ліво:
            основа.append((попередня, ліво, замкнено, False, "між"))
        основа.append((ліво, право, True, True, "смуга"))
        попередня, замкнено = право, False
    if попередня < верх:
        основа.append((попередня, верх, замкнено, True, "між"))
    return основа


def складники(бібліотека, V, C):
    """Ваги сталої суміші: [(вага, v, c)], c=0 чи v=10 — сірий (None).

    Повторює гілки _munsell_specification_to_xyY і munsell_specification_to_xy
    для запису 12 цифр; суміш звіряє з прямим методом перевірка моделі.
    """
    V, C = float(f"{V:.12g}"), float(f"{C:.12g}")
    if бібліотека.utilities.is_integer(V):
        значення = [(1.0, round(V))]
    else:
        Y = бібліотека.notation.munsell.luminance_ASTMD1535
        низ = math.floor(V)
        t = (float(Y(V)) - float(Y(низ))) / (float(Y(низ + 1)) - float(Y(низ)))
        значення = [(1 - t, низ), (t, низ + 1)]
    if C % 2 == 0:
        хроми = [(1.0, C)]
    else:
        низ = 2 * math.floor(C / 2)
        s = (C - низ) / 2
        хроми = [(1 - s, низ), (s, низ + 2)]
    return [(wv * wc, None if v == 10 or c == 0 else (v, c))
            for wv, v in значення for wc, c in хроми if wv * wc != 0]


def овоїд(бібліотека, H, v, c):
    """Точка овоїда (v, c) Colour при ASTM H або None без даних."""
    h, код = тон(бібліотека, H)
    try:
        return tuple(float(x) for x in
                     бібліотека.notation.munsell.xy_from_renotation_ovoid([h, v, c, код]))
    except (AssertionError, ValueError):
        return None


def модель_члена(бібліотека, v, c, від, до):
    """Лінійна чи радіальна модель точки овоїда у відкритій частині (від, до).

    Вид читає interpolation_method_from_renotation_ovoid; лінійна — xy = α + β·u,
    радіальна — ρ, φ (радіани) лінійні за u = H − від. Модель звіряє всі проби.
    """
    частки = [(i + 0.5) / ПРОБИ for i in range(ПРОБИ)]
    проби = [(від + (до - від) * t, овоїд(бібліотека, від + (до - від) * t, v, c)) for t in частки]
    if any(p is None for _, p in проби):
        if any(p is not None for _, p in проби):
            raise ValueError(f"Непостійні дані овоїда {(v, c)} у ({від}, {до})")
        return None
    h, код = тон(бібліотека, (від + до) / 2)
    вид = бібліотека.notation.munsell.interpolation_method_from_renotation_ovoid([h, v, c, код])
    (u1, p1), (u2, p2) = (проби[0][0] - від, проби[0][1]), (проби[-1][0] - від, проби[-1][1])
    if вид == "Linear":
        β = [(p2[i] - p1[i]) / (u2 - u1) for i in range(2)]
        член = {"вид": "лінійна", "α": [p1[i] - β[i] * u1 for i in range(2)], "β": β}
    elif вид == "Radial":
        сірий = [float(x) for x in бібліотека.notation.munsell.CCS_ILLUMINANT_MUNSELL]
        φ, попередній = [], None
        for _, p in проби:
            кут = math.atan2(p[1] - сірий[1], p[0] - сірий[0])
            if попередній is not None:
                кут += 2 * math.pi * round((попередній - кут) / (2 * math.pi))
            φ.append(кут)
            попередній = кут
        ρ = [math.hypot(p[0] - сірий[0], p[1] - сірий[1]) for _, p in проби]
        ρ1 = (ρ[-1] - ρ[0]) / (u2 - u1)
        φ1 = (φ[-1] - φ[0]) / (u2 - u1)
        член = {"вид": "радіальна", "сірий": сірий, "ρ": [ρ[0] - ρ1 * u1, ρ1],
                "φ": [φ[0] - φ1 * u1, φ1]}
    else:
        raise ValueError(f"Невідомий вид інтерполяції {вид}")
    for H, p in проби:
        q = значення_члена(член, H - від)
        if max(abs(q[0] - p[0]), abs(q[1] - p[1])) > МОДЕЛЬ:
            raise ValueError(f"Модель овоїда {(v, c)} не відтворює Colour при H={H}")
    return член


def значення_члена(член, u):
    """xy члена моделі при u = H − від."""
    if член["вид"] == "лінійна":
        return tuple(член["α"][i] + член["β"][i] * u for i in range(2))
    ρ = член["ρ"][0] + член["ρ"][1] * u
    φ = член["φ"][0] + член["φ"][1] * u
    return член["сірий"][0] + ρ * math.cos(φ), член["сірий"][1] + ρ * math.sin(φ)


# Обмеження XYZ ≥ 0 при Y>0: коефіцієнти (кx, кy, стала) лінійної форми від xy.
ОБМЕЖЕННЯ = {"y": (0.0, 1.0, 0.0), "x": (1.0, 0.0, 0.0), "z": (-1.0, -1.0, 1.0)}


def обмеження(модель, назва):
    """Розкладає обмеження на сталу, нахил за u і радіальні доданки w·ρ·(a·cos φ + b·sin φ)."""
    кx, кy, стала = ОБМЕЖЕННЯ[назва]
    A, B, радіальні = стала, 0.0, []
    for вага, член in модель:
        if член["вид"] == "стала":
            A += вага * (кx * член["xy"][0] + кy * член["xy"][1])
        elif член["вид"] == "лінійна":
            A += вага * (кx * член["α"][0] + кy * член["α"][1])
            B += вага * (кx * член["β"][0] + кy * член["β"][1])
        else:
            A += вага * (кx * член["сірий"][0] + кy * член["сірий"][1])
            радіальні.append((вага, кx, кy, член["ρ"], член["φ"]))
    return A, B, радіальні


def g(форма, u):
    """Значення обмеження та його першої похідної."""
    A, B, радіальні = форма
    значення, похідна = A + B * u, B
    for w, a, b, (ρ0, ρ1), (φ0, φ1) in радіальні:
        ρ, φ = ρ0 + ρ1 * u, φ0 + φ1 * u
        т, т1 = a * math.cos(φ) + b * math.sin(φ), -a * math.sin(φ) + b * math.cos(φ)
        значення += w * ρ * т
        похідна += w * (ρ1 * т + ρ * φ1 * т1)
    return значення, похідна


def межі_похідних(форма, p, q):
    """Верхні межі |g'| і |g''| на [p, q] за |a·cos + b·sin| ≤ |a| + |b|."""
    _, B, радіальні = форма
    L1, L2 = abs(B), 0.0
    for w, a, b, (ρ0, ρ1), (_, φ1) in радіальні:
        m = abs(w) * (abs(a) + abs(b))
        ρмакс = max(abs(ρ0 + ρ1 * p), abs(ρ0 + ρ1 * q))
        L1 += m * (abs(ρ1) + ρмакс * abs(φ1))
        L2 += m * (2 * abs(ρ1 * φ1) + ρмакс * φ1 * φ1)
    return L1, L2


def доведені_знаки(форма, низ, верх):
    """Ділить [низ, верх] (u) на проміжки зі сталим доведеним знаком і дужки коренів.

    Сталий знак: |g(m)| > L1·h + запас. Монотонність: |g'(m)| > L2·h + запас —
    тоді корінь лише за зміни знака кінців. Дає [(p, q, знак | "корінь")], кроків.
    """
    результат, стек, кроків = [], [(низ, верх, 0)], 0
    while стек:
        p, q, глибина = стек.pop()
        кроків += 1
        m, h = (p + q) / 2, (q - p) / 2
        значення, похідна = g(форма, m)
        L1, L2 = межі_похідних(форма, p, q)
        if abs(значення) > L1 * h + ЗАПАС:
            результат.append((p, q, 1 if значення > 0 else -1))
            continue
        if abs(похідна) > L2 * h + ЗАПАС:
            gp, gq = g(форма, p)[0], g(форма, q)[0]
            if abs(gp) > ЗАПАС and abs(gq) > ЗАПАС:
                результат.append((p, q, "корінь") if (gp > 0) != (gq > 0)
                                 else (p, q, 1 if gp > 0 else -1))
                continue
        if глибина >= ГЛИБИНА:
            raise ValueError(f"Знак обмеження не доведено на [{p}, {q}]")
        стек += [(m, q, глибина + 1), (p, m, глибина + 1)]
    return sorted(результат), кроків


def зробити_xyz(бібліотека):
    """Прямий предикат XYZ ≥ 0 чинного перетворення; None — без даних."""
    перетворити = ОСНОВА.зробити_перетворення(бібліотека)

    def придатне(H, V, C):
        try:
            перетворити(H, V, C)
        except ValueError as помилка:
            if "Непридатний XYZ" in str(помилка):
                return False
            return None
        except AssertionError:
            return None
        return True
    return придатне


def частина_між(бібліотека, придатне, вимір, V, C, від, до, зв, зд, суміш):
    """Модель, доведені знаки й область відкритої частини (від, до) між смугами."""
    модель = []
    for вага, член in суміш:
        if член is None:
            сірий = [float(x) for x in бібліотека.notation.munsell.CCS_ILLUMINANT_MUNSELL]
            модель.append((вага, {"вид": "стала", "xy": сірий}))
            continue
        опис = модель_члена(бібліотека, *член, від, до)
        if опис is None:
            return None, [], 0
        модель.append((вага, dict(опис, v=член[0], c=член[1])))
    # Суміш звіряється з прямим методом у тих самих частках, що й члени.
    for t in (0.1, 0.5, 0.9):
        H = від + (до - від) * t
        прямо = вимір(H, V, C)
        x = sum(в * значення_члена_повне(ч, H - від)[0] for в, ч in модель)
        y = sum(в * значення_члена_повне(ч, H - від)[1] for в, ч in модель)
        if прямо is None or max(abs(x - прямо[0]), abs(y - прямо[1])) > МОДЕЛЬ:
            raise ValueError(f"Суміш не відтворює Colour при H={H}")
    кроків, корені, знаки = 0, [], {}
    for назва in ОБМЕЖЕННЯ:
        форма = обмеження(модель, назва)
        проміжки, к = доведені_знаки(форма, 0.0, до - від)
        кроків += к
        знаки[назва] = проміжки
        корені += [(від + p, від + q, назва) for p, q, знак in проміжки if знак == "корінь"]
    точки = sorted({від, до} | {уточнити(придатне, V, C, p, q) for p, q, _ in корені})
    шматки = []
    for i in range(len(точки) - 1):
        p, q = точки[i], точки[i + 1]
        if p == q:
            continue
        m = (p + q) / 2
        if придатне(m, V, C):
            шматки.append((p, q, зв if p == від else True, зд if q == до else True,
                           ["частина" if p == від else "XYZ", "частина" if q == до else "XYZ"]))
    return модель, шматки, кроків


def значення_члена_повне(член, u):
    """xy члена разом зі сталим сірим."""
    return tuple(член["xy"]) if член["вид"] == "стала" else значення_члена(член, u)


def уточнити(придатне, V, C, p, q):
    """Останній float з боку придатного кінця дужки — межа прямого методу."""
    a, b = придатне(p, V, C), придатне(q, V, C)
    if a is None or b is None or a == b:
        raise ValueError(f"Дужка кореня XYZ без зміни прямого методу: [{p}, {q}]")
    всередині, назовні = (p, q) if a else (q, p)
    return РЕБРА.межа(lambda x: придатне(x, V, C), всередині, назовні)


def зшити_сусідні(область):
    """Зливає замкнені інтервали, між якими немає float (поділ смуги 10k)."""
    результат = []
    for інтервал in область:
        if (результат and результат[-1]["замкнено"][1] and інтервал["замкнено"][0]
                and math.nextafter(результат[-1]["до"], math.inf) == інтервал["від"]):
            результат[-1].update(до=інтервал["до"],
                                 замкнено=[результат[-1]["замкнено"][0], інтервал["замкнено"][1]])
            результат[-1]["межі"][1] = інтервал["межі"][1]
            continue
        результат.append(інтервал)
    return результат


def ребро(бібліотека, придатне, вимір, запис):
    """Область, частини й доведення ребра вздовж H."""
    V, C = запис["фіксовані"]
    низ, верх = ЗШИВАННЯ.число(запис["інтервал"][0]), ЗШИВАННЯ.число(запис["інтервал"][1])
    смуги = смуги_тону(бібліотека, низ, верх)
    суміш = складники(бібліотека, V, C)
    частини, шматки, кроків = [], [], 0
    for від, до, зв, зд, (a, b, вид) in РЕБРА.частини(низ, верх, основа_H(смуги, низ, верх)):
        if вид == "смуга":
            точки = [вимір(x, V, C) for x in (a, (a + b) / 2, b)]
            if any(p != точки[1] for p in точки):
                raise ValueError(f"xy не сталий у смузі тону [{a}, {b}] при V={V}, C={C}: {точки}")
            шматок = точки[1] and РЕБРА.допустиме(точки[1][:2], [0.0, 0.0], від, до, зв, зд)
            частини.append({"вид": "смуга", "від": від, "до": до, "дані": точки[1] is not None})
            if шматок:
                шматки.append(шматок)
            continue
        модель, свої, к = частина_між(бібліотека, придатне, вимір, V, C, a, b, зв, зд, суміш)
        кроків += к
        свої = [(max(p, від), min(q, до), зв if p <= від else з1, зд if q >= до else з2, м)
                for p, q, з1, з2, м in свої if q >= від and p <= до]
        шматки += свої
        частини.append({"вид": "між", "від": a, "до": b, "дані": модель is not None,
                        "члени": None if модель is None else
                        [dict(вага=в, **{k: v for k, v in ч.items()}) for в, ч in модель]})
    область = зшити_сусідні(РЕБРА.злити(шматки, низ, верх, "край ребра"))
    return {"клас": "H", "V": V, "C": C, "область": область, "частини": частини,
            "кроків_доведення": кроків}


def породити():
    """Звіряє вихід ребер повним повторним породженням і переносить відкладені H-ребра."""
    бібліотека = ОСНОВА.залежності()
    попереднє = json.loads(ВХІД.read_text(encoding="utf-8"))
    if РЕБРА.серіалізувати(РЕБРА.породити()) != ВХІД.read_text(encoding="utf-8"):
        raise ValueError("Ребра не відповідають чинному методу")
