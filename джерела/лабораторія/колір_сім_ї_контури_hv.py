"""Переносить повні скінченні внутрішні H/V-грані сімей у Lab та θ/L*/C*.

Читає спільні поверхні джерела й повторно використовує метод C-граней.
Вихід лабораторний: похибка вибіркова, оболонки ще не зшиті.
"""
import argparse
from functools import lru_cache
import importlib.util
import itertools
import json
from pathlib import Path
import sys


ШЛЯХ = Path(__file__).with_name("колір_сім_ї_контури.py")
СПЕЦИФІКАЦІЯ = importlib.util.spec_from_file_location("контури_основа", ШЛЯХ)
ОСНОВА = importlib.util.module_from_spec(СПЕЦИФІКАЦІЯ)
СПЕЦИФІКАЦІЯ.loader.exec_module(ОСНОВА)
ВХІД = ОСНОВА.ВХІД
ВИХІД = Path(__file__).with_suffix(".json")


def причина_відкладення(грань):
    """Обирає весь клас H/V-граней: скінченний C>0, внутрішній V."""
    if грань["вісь"] == "C":
        return ОСНОВА.причина_відкладення(грань)
    перший, C = грань["інтервали"]
    if C[1] == "+inf":
        return "Необмежений C-промінь: потрібне окреме подання області визначеності"
    if C[0] <= 0:
        return "C=0: потрібне окреме подання нейтральної осі"
    V = перший if грань["вісь"] == "H" else [грань["координата"]] * 2
    if V[0] <= 0 or V[1] >= 10:
        return "V=0/10: потрібна область визначеності й окреме подання кінців"
    return None


def координати_джерела(вісь, стала, перша, друга):
    """Відновлює H/V/C із двох вільних параметрів орієнтованої грані."""
    if вісь == "H":
        return стала, перша, друга
    if вісь == "V":
        return перша, стала, друга
    raise ValueError(f"Очікується H/V-грань, отримано {вісь}")


def параметризувати(перетворити, вісь):
    """Адаптує координати H/V-грані до спільного двопараметричного методу."""
    @lru_cache(maxsize=None)
    def поверхня(перша, друга, стала):
        """Обчислює координати через єдиний renotation/Bradford/Lab-метод."""
        return перетворити(*координати_джерела(вісь, стала, перша, друга))

    return поверхня


def початкові_ділянки(грань):
    """Ріже параметри в усіх вузлах інтерполяції renotation H, V та C."""
    перша, C = грань["інтервали"]
    вузли = range(11) if грань["вісь"] == "H" else [2.5 * i for i in range(41)]
    # Хрома інтерполюється між парними овоїдами; початкові ділянки
    # не перетинають ці злами. Верхня C скінченна за контрактом класу.
    return list(itertools.product(
        ОСНОВА.поділити(перша, вузли),
        ОСНОВА.поділити(C, range(0, int(C[1]) + 2, 2))))


def перевірити_область(грань):
    """Відмовляє, якщо будь-яка повна початкова ділянка виходить за renotation."""
    from colour.notation.munsell import (maximum_chroma_from_renotation,
                                        munsell_colour_to_munsell_specification)
    запаси = []
    for перша, C in початкові_ділянки(грань):
        H, V, _ = координати_джерела(
            грань["вісь"], грань["координата"], sum(перша) / 2, C[1])
        # Для сталої H мінімум у відкритій V-смузі до V=9 сталий;
        # вище 9 стеля монотонно спадає, тому беремо верхній V.
        if грань["вісь"] == "H" and перша[1] > 9:
            V = перша[1]
        h, V, _, код = munsell_colour_to_munsell_specification(ОСНОВА.позначення(H, V, C[1]))
        стеля = maximum_chroma_from_renotation([h, V, код])
        if C[1] > стеля:
            raise ValueError(f"Поза renotation: {грань}, ділянка {(перша, C)}, стеля {стеля}")
        запаси.append(float(стеля - C[1]))
    return {"ділянок": len(запаси), "мінімальний_запас_C": min(запаси)}


def породити():
    """Породжує H/V-грані та повний облік разом із попереднім класом C-граней."""
    бібліотека = ОСНОВА.залежності()
    перетворити = ОСНОВА.зробити_перетворення(бібліотека)
    поверхні = {вісь: параметризувати(перетворити, вісь) for вісь in "HV"}
    вхід = json.loads(ВХІД.read_text(encoding="utf-8"))
    попередній = json.loads(ОСНОВА.ВИХІД.read_text(encoding="utf-8"))
    раніше = {запис["грань"] for запис in попередній["грані"]}
    очікувані = {i for i, грань in enumerate(вхід["межі"])
                 if грань["вісь"] == "C" and ОСНОВА.причина_відкладення(грань) is None}
    if раніше != очікувані or len(попередній["грані"]) != len(раніше):
        raise ValueError("Попередній вихід не покриває рівно весь клас C-граней")
    for запис in попередній["грані"]:
        if запис["джерело"] != вхід["межі"][запис["грань"]]:
            raise ValueError("Попередній вихід має інше джерело")
    # Походження попереднього виходу звіряється до використання його обліку.
    for запис in попередній["походження"]:
        назва = запис["файл"]
        if назва.startswith("colour/"):
            шлях = Path(бібліотека.__file__).parent / назва.removeprefix("colour/")
        else:
            шлях = ВХІД.parent / назва
            if not шлях.is_file():
                шлях = ОСНОВА.ДЖЕРЕЛА / назва
        if ОСНОВА.походження([(назва, шлях)])[0] != запис:
            raise ValueError(f"Походження попереднього виходу застаріло: {назва}")
    артефакт = {
        "формат": 1, "версії": ОСНОВА.ВЕРСІЇ,
        "походження": ОСНОВА.походження([
            (ВХІД.name, ВХІД), (ВИХІД.with_suffix(".py").name, __file__),
            (ШЛЯХ.name, ШЛЯХ), (ОСНОВА.ВИХІД.name, ОСНОВА.ВИХІД)]),
        "походження_перетворення": попередній["походження"],
        "статус": "Лабораторна апроксимація H/V-граней; похибка вибіркова, не гарантована; не вхід продукту",
        "простір": попередній["простір"], "метод": попередній["метод"],
        "цілі_похибки": ОСНОВА.РЕЄСТР["похибка"]["val"],
        "порядок_похибок": попередній["порядок_похибок"],
        "порядок_параметрів": {"H": ["V", "C"], "V": ["H", "C"]},
        "подання": "Параметри: повний прямокутник; вузли 00,10,11,01: [Lab, θLC]; трикутники Lab 012 і 023; θLC всередині = координати_з_lab(інтерполянт Lab)",
        "раніше": sorted(раніше), "грані": [], "відкладені": [],
    }
    for номер, грань in enumerate(вхід["межі"]):
        if номер in раніше:
            continue
        причина = причина_відкладення(грань)
        if причина:
            артефакт["відкладені"].append({"грань": номер, "причина": причина})
            continue
        область = перевірити_область(грань)
        поверхня = поверхні[грань["вісь"]]
        стала = грань["координата"]
        ділянки = []
        for межі in початкові_ділянки(грань):
            for ділянка in ОСНОВА.породити_ділянки(поверхня, стала, межі):
                ділянка["параметри"] = ділянка.pop("HV")
                ділянки.append(ділянка)
        перевірка = list(itertools.product((0.211324865405187, 0.788675134594813), repeat=2))
        for ділянка in ділянки:
            вимір = ОСНОВА.перевірити_ділянку(
                поверхня, стала, ділянка["параметри"], ділянка["вузли"], перевірка)
            if any(x > ціль for x, ціль in zip(вимір, артефакт["цілі_похибки"])):
                raise ValueError(f"Відкладена перевірка не пройшла, грань {номер}: {вимір}")
            ділянка["перевірка"] = вимір
        артефакт["грані"].append({"грань": номер, "джерело": грань,
                                  "область_renotation": область, "ділянки": ділянки})
        print(f"Грань {номер} ({грань['вісь']}): ділянок {len(ділянки)}", flush=True)
    return артефакт


def головна():
    """Записує або відтворює лабораторний артефакт скінченних H/V-граней."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--записати", action="store_true")
    парсер.add_argument("--вихід", type=Path, default=ВИХІД)
    аргументи = парсер.parse_args()
    артефакт = ОСНОВА.округлити(породити())
    текст = json.dumps(артефакт, ensure_ascii=False, allow_nan=False, separators=(",", ":")) + "\n"
    if аргументи.записати:
        аргументи.вихід.write_text(текст, encoding="utf-8", newline="\n")
    elif not аргументи.вихід.exists() or аргументи.вихід.read_text(encoding="utf-8") != текст:
        парсер.exit(1, "Артефакт відсутній або відрізняється від виходу методу\n")
    print(f"Перенесено H/V-граней {len(артефакт['грані'])}; раніше {len(артефакт['раніше'])}; відкладено {len(артефакт['відкладені'])}")


if __name__ == "__main__":
    головна()
