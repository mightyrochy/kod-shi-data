"""Переносить скінченні внутрішні C-грані сімей через renotation у θ/L*/C*.

Лабораторний вихід: параметризовані ділянки з вибірковою оцінкою похибки,
не визначення сімей продукту й не доведена верхня межа похибки між пробами.
Повний перелік граней зберігається, зокрема ще не перенесених.
"""
import argparse
from functools import lru_cache
import hashlib
import importlib.metadata
import inspect
import itertools
import json
import math
from pathlib import Path
import sys


ДЖЕРЕЛА = Path(__file__).resolve().parents[1]
if str(ДЖЕРЕЛА) not in sys.path:
    sys.path.insert(0, str(ДЖЕРЕЛА))

from colorspace import (БІЛІ, _BRADFORD as BRADFORD,
                       _BRADFORD_ОБЕРНЕНА as BRADFORD_ОБЕРНЕНА,
                       _множ as множ, from_xyz, lch, у_коло_художника)


ВХІД = Path(__file__).with_name("колір_сім_ї_межі.json")
ВИХІД = Path(__file__).with_suffix(".json")
РЕЄСТР = {
    "похибка": {"t": "T3", "val": (0.1, 0.25, 0.1, 0.1), "прав": [],
                "джерело": "Числова ціль апроксимації: ΔLab76, θ°, L*, C*; не допуск сім'ї"},
    "глибина": {"t": "T3", "val": 9, "прав": [],
                "джерело": "Відмова замість неперевіреної апроксимації після 9 поділів"},
}
ВЕРСІЇ = {"colour-science": "0.4.6", "numpy": "2.2.6", "scipy": "1.15.3"}


def залежності():
    """Відмовляє при іншому рушії renotation, перш ніж породжувати координати."""
    for назва, версія in ВЕРСІЇ.items():
        if importlib.metadata.version(назва) != версія:
            raise ValueError(f"Потрібно {назва}=={версія}")
    import colour
    return colour


def позначення(H, V, C):
    """Перекладає ASTM H у позначення Манселла без зсуву на одиницю."""
    if not all(math.isfinite(x) for x in (H, V, C)):
        raise ValueError("Нескінченна або непридатна координата")
    if not 1 <= H <= 101 or not 0 < V < 10 or C <= 0:
        raise ValueError("Поза обраною невиродженою областю")
    H %= 100
    if H == 0:
        тон = "10RP"
    else:
        сектор = math.ceil(H / 10) - 1
        код = ("R", "YR", "Y", "GY", "G", "BG", "B", "PB", "P", "RP")[сектор]
        тон = f"{H - 10 * сектор:.12g}{код}"
    return f"{тон} {V:.12g}/{C:.12g}"


def зробити_перетворення(бібліотека):
    """Збирає renotation C → Bradford D65 → єдиний Lab і чинне коло художника."""
    від = множ(BRADFORD, БІЛІ["C"])
    до = множ(BRADFORD, БІЛІ["D65"])

    @lru_cache(maxsize=None)
    def перетворити(H, V, C):
        """Дає Lab та θ/L*/C*; непридатна renotation зупиняє породження."""
        xyY = бібліотека.notation.munsell_colour_to_xyY(позначення(H, V, C))
        # ASTM-вихід уже відносно ідеального дифузора: повторного ×0.975 немає.
        xyz = бібліотека.xyY_to_XYZ(xyY)
        if not all(math.isfinite(float(x)) for x in xyz) or min(xyz) < 0:
            raise ValueError(f"Непридатний XYZ для {(H, V, C)}: {xyz}")
        lms = множ(BRADFORD, xyz)
        lab = from_xyz(*множ(BRADFORD_ОБЕРНЕНА,
                            tuple(lms[i] * до[i] / від[i] for i in range(3))))
        return tuple(lab), координати_з_lab(lab)

    return перетворити


def координати_з_lab(lab):
    """Дає координати кола з Lab через чинне визначення, без другого інтерполянта θ."""
    L, C, h = lch(lab)
    if C <= 0 or not all(math.isfinite(x) for x in lab):
        raise ValueError("Невизначений тон або непридатний Lab")
    return у_коло_художника(h), L, C


def причина_відкладення(грань):
    """Вибирає весь клас скінченних внутрішніх C-граней, без ручних ID."""
    if грань["вісь"] != "C":
        return "Наступний клас: H/V-грані, зокрема необмежені промені C"
    if грань["координата"] == 0:
        return "C=0: виродження тону; потрібне окреме подання нейтральної осі"
    if грань["інтервали"][1][0] <= 0 or грань["інтервали"][1][1] >= 10:
        return "V=0/10: потрібна область визначеності й окреме подання кінців"
    return None


def розгорнути(θ, опора):
    """Вибирає неперервну гілку кута поблизу опори, зберігаючи перехід 360°."""
    return опора + (θ - опора + 180) % 360 - 180


def наблизити(вузли, u, v):
    """Лінійно інтерполює один із двох трикутників прямокутної ділянки."""
    if u >= v:
        ваги = (1 - u, u - v, v, 0)
    else:
        ваги = (1 - v, 0, u, v - u)
    return tuple(sum(вага * вузол[i] for вага, вузол in zip(ваги, вузли))
                 for i in range(len(вузли[0])))


def похибки(точне, наближене):
    """Міряє похибку Lab та кожної координати поверхні θ/L*/C* окремо."""
    lab, координати = точне
    lab_набл, координати_набл = наближене
    return (math.dist(lab, lab_набл),
            abs(розгорнути(координати[0], координати_набл[0]) - координати_набл[0]),
            abs(координати[1] - координати_набл[1]),
            abs(координати[2] - координати_набл[2]))


def перевірити_ділянку(перетворити, C, межі, вузли, точки):
    """Зіставляє інтерполянт із прямим перетворенням у заданих пробах."""
    (H0, H1), (V0, V1) = межі
    максимуми = [0.0] * 4
    for u, v in точки:
        точне = перетворити(H0 + u * (H1 - H0), V0 + v * (V1 - V0), C)
        lab = наблизити([вузол[0] for вузол in вузли], u, v)
        наближене = lab, координати_з_lab(lab)
        максимуми = list(map(max, максимуми, похибки(точне, наближене)))
    return максимуми


def породити_ділянки(перетворити, C, межі, глибина=0):
    """Ділить усю параметричну область до проходження контрольних проб."""
    (H0, H1), (V0, V1) = межі
    вузли = [перетворити(H, V, C) for H, V in ((H0, V0), (H1, V0), (H1, V1), (H0, V1))]
    опора = вузли[0][1][0]
    вузли = [(lab, (розгорнути(θ, опора), L, хрома)) for lab, (θ, L, хрома) in вузли]
    контроль = list(itertools.product((0.25, 0.5, 0.75), repeat=2))
    контроль += [(0, 0.5), (0.5, 0), (1, 0.5), (0.5, 1)]
    вимір = перевірити_ділянку(перетворити, C, межі, вузли, контроль)
    # Запас для відкладеної перевірки в інших точках; це не доказ між пробами.
    if all(x <= ціль / 2 for x, ціль in zip(вимір, РЕЄСТР["похибка"]["val"])):
        yield {"HV": межі, "вузли": вузли, "контроль": вимір}
        return
    if глибина >= РЕЄСТР["глибина"]["val"]:
        raise ValueError(f"Не досягнуто числової цілі: C={C}, HV={межі}, похибка={вимір}")
    Hm, Vm = (H0 + H1) / 2, (V0 + V1) / 2
    for H, V in itertools.product(((H0, Hm), (Hm, H1)), ((V0, Vm), (Vm, V1))):
        yield from породити_ділянки(перетворити, C, (H, V), глибина + 1)


def поділити(інтервал, вузли):
    """Розрізає інтервал у вузлах renotation до подальшого наближення."""
    низ, верх = інтервал
    краї = [низ] + [x for x in вузли if низ < x < верх] + [верх]
    return list(zip(краї, краї[1:]))


def походження(шляхи):
    """Фіксує SHA-256 LF-текстів, які визначили координати й алгоритм."""
    return [{"файл": назва, "sha256_lf": hashlib.sha256(
        Path(шлях).read_text(encoding="utf-8").encode("utf-8")).hexdigest()}
        for назва, шлях in шляхи]


def породити():
    """Породжує обраний клас поверхонь та облік кожної з вихідних граней."""
    бібліотека = залежності()
    перетворити = зробити_перетворення(бібліотека)
    вхід = json.loads(ВХІД.read_text(encoding="utf-8"))
    from colour.notation import munsell
    from colour.notation.datasets.munsell import all as дані
    шляхи = [(ВХІД.name, ВХІД), (Path(__file__).name, __file__),
             ("colour/notation/munsell.py", inspect.getfile(munsell)),
             ("colour/notation/datasets/munsell/all.py", inspect.getfile(дані))]
    шляхи += [(назва, ДЖЕРЕЛА / назва) for назва in
              ("колір_простір_перетворення.py", "колір_простір_риси.py", "колір_простір_реєстр.py")]
    артефакт = {
        "формат": 1, "версії": ВЕРСІЇ, "походження": походження(шляхи),
        "статус": "Лабораторна апроксимація C-граней; похибка вибіркова, не гарантована; не вхід продукту",
        "простір": "Lab D65 та θ/L*/C* чинного кола художника; θ локально розгорнуто",
        "метод": "Colour 0.4.6 ASTM renotation C → XYZ → Bradford D65 → Lab → чинне коло; Y без повторного ×0.975",
        "цілі_похибки": РЕЄСТР["похибка"]["val"],
        "порядок_похибок": ["ΔLab76", "θ°", "L*", "C*"],
        "подання": "HV: повний прямокутник; вузли 00,10,11,01: [Lab, θLC]; трикутники Lab 012 і 023; θLC всередині = координати_з_lab(інтерполянт Lab), не інтерполянт θLC",
        "відкладені": [], "грані": [],
    }
    for номер, грань in enumerate(вхід["межі"]):
        причина = причина_відкладення(грань)
        if причина:
            артефакт["відкладені"].append({"грань": номер, "причина": причина})
            continue
        C = грань["координата"]
        H, V = грань["інтервали"]
        ділянки = []
        for межі in itertools.product(поділити(H, [2.5 * i for i in range(41)]),
                                     поділити(V, range(11))):
            ділянки.extend(породити_ділянки(перетворити, C, межі))
        # Точки цієї перевірки не брали участі у виборі поділу.
        перевірка = list(itertools.product((0.211324865405187, 0.788675134594813), repeat=2))
        for ділянка in ділянки:
            вимір = перевірити_ділянку(перетворити, C, ділянка["HV"], ділянка["вузли"], перевірка)
            if any(x > ціль for x, ціль in zip(вимір, РЕЄСТР["похибка"]["val"])):
                raise ValueError(f"Відкладена перевірка не пройшла, грань {номер}: {вимір}")
            ділянка["перевірка"] = вимір
        артефакт["грані"].append({"грань": номер, "джерело": грань, "ділянки": ділянки})
        print(f"Грань {номер}: ділянок {len(ділянки)}", flush=True)
    return артефакт


def округлити(значення):
    """Записує координати з точністю значно вищою за числові цілі апроксимації."""
    if isinstance(значення, float):
        return round(значення, 9)
    if isinstance(значення, (list, tuple)):
        return [округлити(x) for x in значення]
    if isinstance(значення, dict):
        return {k: округлити(v) for k, v in значення.items()}
    return значення


def головна():
    """Записує або повністю відтворює лабораторний артефакт офлайн."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--записати", action="store_true")
    парсер.add_argument("--вихід", type=Path, default=ВИХІД)
    аргументи = парсер.parse_args()
    артефакт = округлити(породити())
    текст = json.dumps(артефакт, ensure_ascii=False, allow_nan=False, separators=(",", ":")) + "\n"
    if аргументи.записати:
        аргументи.вихід.write_text(текст, encoding="utf-8", newline="\n")
    elif not аргументи.вихід.exists() or аргументи.вихід.read_text(encoding="utf-8") != текст:
        парсер.exit(1, "Артефакт відсутній або відрізняється від виходу методу\n")
    print(f"Перенесено граней {len(артефакт['грані'])}; відкладено {len(артефакт['відкладені'])}")


if __name__ == "__main__":
    головна()
