def _зсув(F, риса, новий_lab, джерело, σ):
    """ЗНАЙДЕНО РОЗБОРОМ: тут оновлювались лише L/C/h/a/b/rel_C, а ПОХІДНІ поля
    (ITA, ITA_смуга, depth_band, тепло_сила, тепло_клас, undertone, олива_член; для
    волосся — HT і каст) лишались від СТАРОГО кольору. Засмага на 3 кроки рухала
    L* 61.3->47.8, а ITA далі показувала 33.2 «intermediate» замість -6 «brown», і
    palette.температура судила шкіру, якої вже нема. Тепер похідні перераховуються
    одним місцем — colorspace.перерахувати_рису."""
    F = copy.deepcopy(F)
    старий = F.get(риса)
    if not старий: raise ValueError(f"у профілі нема риси «{риса}»")
    L, C, h = lch(новий_lab)
    F = перерахувати_рису(F, риса, tuple(новий_lab))
    F[риса]["походження"] = dict(джерело=джерело, σ_L=σ,
                                 було_L=старий["L"], зсув_L=round(L - старий["L"], 1),
                                 похідні="перераховано з нового кольору (ITA/тепло/підтон)")
    return F

def перефарбування(F, новий_колір, заявлено=True):
    """Найважча правка: волосся несе контраст особи майже сам (Lamport), тож зсув
    його світлоти рухає ВСІ вікна біля обличчя. Заявлений колір — не вимір."""
    lab = hx(новий_колір) if isinstance(новий_колір, str) else tuple(новий_колір)
    риса = next((k for k in F if k.startswith("волосся")), None)
    джерело = "заявлено_фарбування" if заявлено else "вимір_протокол"
    F2 = _зсув(F, риса, lab, джерело, Σ[джерело])
    # інші голоси волосся (балаяж) після суцільного фарбування зникають
    for k in [k for k in F2 if k.startswith("волосся") and k != риса]:
        F2.pop(k)
    return F2

def засмага(F, крок_ITA=None, новий_lab=None, заявлено=True):
    """Засмага рухає шкіру вниз по L* і по ITA. Крок задається або виміром, або
    заявою на кшталт «на два тони темніше» — і це знову не одне й те саме."""
    риса = "шкіра"
    if новий_lab is None:
        if крок_ITA is None: raise ValueError("треба або новий вимір, або крок")
        L, a, b = F[риса]["L"], F[риса]["a"], F[риса]["b"]
        новий_lab = (max(15.0, L - 4.5*крок_ITA), a + 0.6*крок_ITA, b + 1.2*крок_ITA)
    джерело = "заявлено_засмага" if заявлено else "вимір_протокол"
    return _зсув(F, риса, новий_lab, джерело, Σ[джерело])

def макіяж(F, режим="денний"):
    """Макіяж, ЗАЯВЛЕНИЙ РЕЖИМОМ, коли кольору нема. Піднімає ЕФЕКТИВНИЙ контраст
    біля обличчя; не правка риси, а режим зчитування — тому окремим полем.

    ⚠ ТИХИЙ ДВІЙНИК, ЗНАЙДЕНИЙ ПРОГОНОМ І ЗНЯТИЙ ТУТ. Ця функція несла ВЛАСНУ
    таблицю приросту {нема 0, денний 4, вечірній 12}, тоді як живий шлях рахує
    той самий приріст у `face_contrast` від константи K-CLR-03
    (`ВАЖІЛЬ_МАКІЯЖУ_L`, «один крок Манселл-Value ≈ 10 L*»). Дві відповіді на одне
    питання в двох модулях — рівно те, що ловить гейт D, і він їх не спіймав, бо
    імена різні. Гейт бачить однакові ЧИСЛА під однаковими ІМЕНАМИ, а тут були
    різні числа під різними іменами: 12 проти 10 за «повний макіяж».
    Функцію не викликав ніхто, тож зміна нічого не ламає — але ЛИШИТИ її було б
    гірше за видалити: мертвий двійник оживає першим, коли хтось шукає готове.

    Тепер число одне: режим — це ЧАСТКА одного кроку, а сам крок живе в
    `face_contrast`. «Вечірній» = повний крок, не більше: правило дає один крок,
    і режим не має права видати більше, ніж дозволило правило.

    ⚠ РЕЖИМ — ЗАПАСНИЙ ШЛЯХ. Коли відомі КОЛЬОРИ макіяжу, важіль МІРЯЄТЬСЯ
    (`face_contrast.важіль_макіяжу`: |ΔL*| зони макіяжу до зони обличчя), і
    вимір заступає режим. Режим лишається для входу без кольору."""
    import face_contrast as _KC
    ЧАСТКА = {"нема": 0.0, "денний": 0.4, "вечірній": 1.0}   # T3: частки кроку
    if режим not in ЧАСТКА: raise ValueError(f"режим із {sorted(ЧАСТКА)}")
    F = copy.deepcopy(F)
    F["_макіяж"] = dict(режим=режим,
                        приріст_контрасту=round(ЧАСТКА[режим] * _KC.ВАЖІЛЬ_МАКІЯЖУ_L, 1),
                        джерело_числа="K-CLR-03 через face_contrast.ВАЖІЛЬ_МАКІЯЖУ_L",
                        σ=Σ["заявлено_макіяж"],
                        чому="темніші вії/брови й губи розширюють діапазон світлоти "
                             "в зоні обличчя, не змінюючи шкіри й волосся",
                        заступається="кольором макіяжу, коли він відомий: тоді "
                                     "важіль міряється, а не заявляється")
    return F

def вікна_біля_обличчя(F, source="protocolized"):
    """Наслідок правки в тому вигляді, в якому його бачить каталог."""
    o = контраст(F, source)
    if not o.get("доступно"): return None
    return dict(контраст=o["value_gap"], рівень=o["рівень"],
                вікно_темніше=_КОЛІР.цільове_вікно(o["L_шкіри"], o["value_gap"], True),
                вікно_світліше=_КОЛІР.цільове_вікно(o["L_шкіри"], o["value_gap"], False),
                σ=σ_профілю(F, source))

