def у_полі_sRGB(L, a, b):
    """Маска вузлів, ближчих до гамуту sRGB за поле: відстань до Lab обрізаного sRGB."""
    import numpy as np
    from колір_простір_перетворення import to_lab
    поле = РЕЄСТР["поле_sRGB"]["val"]
    маска = np.zeros(L.shape, dtype=bool)
    for i in range(L.size):
        rgb = to_rgb(float(L.flat[i]), float(a.flat[i]), float(b.flat[i]))
        if all(-0.25 <= к <= 1.25 for к in rgb):
            обрізане = to_lab(tuple(255 * min(1.0, max(0.0, к)) for к in rgb))
            маска.flat[i] = math.dist(обрізане, (L.flat[i], a.flat[i], b.flat[i])) <= поле
    return маска


