def мітки(H, V, C, клітинки):
    """Номер блока й індекс сім'ї кожної точки H/V/C; нуль хроми — будь-який тон (ахромат)."""
    import numpy as np
    блок = np.zeros(H.shape, dtype=np.int16)
    сім_я = np.full(H.shape, НЕМА, dtype=np.uint8)
    for Hmin, Hmax, Vmin, Vmax, Cmin, Cmax, номер, індекс in клітинки:
        верх_V = (V <= Vmax) if Vmax >= 10 else (V < Vmax)
        м = (H >= Hmin) & (H < Hmax) & (V >= Vmin) & верх_V & (C >= Cmin) & (C < Cmax) & (блок == 0)
        блок[м] = номер
        сім_я[м] = індекс
    return блок, сім_я


def обернути(точки, вузли):
    """Лінійне обернення Lab → (aM, bM, V) на тетраедрах Делоне прямого образу; поза оболонкою — NaN."""
    import numpy as np
    from scipy.interpolate import LinearNDInterpolator
    кут = 2 * np.pi * точки[:, 0] / 100.0
    q = точки[:, 2]
    цілі = np.column_stack([q * np.cos(кут), q * np.sin(кут), точки[:, 1]])
    обернення = LinearNDInterpolator(точки[:, 3:6], цілі)
    вихід = обернення(вузли)
    H = (np.degrees(np.arctan2(вихід[:, 1], вихід[:, 0])) / 3.6) % 100
    H = np.where(H < 1, H + 100, H)
    V = вихід[:, 2]
    C = np.hypot(вихід[:, 0], вихід[:, 1])
    return H, V, C


def межа_C(H, V, межа):
    """Найбільша визначена C у (H, V): білінійно між стовпцями вибірки й рівнем V 10 набору, по колу H."""
    import numpy as np
    рівні = np.array(значення_V() + list(РЕЄСТР["світла_смуга"]["val"]))
    крок_H = РЕЄСТР["крок_H"]["val"]
    таблиця = межа[:, 2].reshape(len(рівні), -1)
    i = np.clip(np.searchsorted(рівні, V, side="right") - 1, 0, len(рівні) - 2)
    t = np.clip((V - рівні[i]) / (рівні[i + 1] - рівні[i]), 0, 1)
    u = (H - 1) / крок_H
    j0 = np.floor(u).astype(int) % таблиця.shape[1]
    j1 = (j0 + 1) % таблиця.shape[1]
    s = u - np.floor(u)
    низ = таблиця[i, j0] * (1 - s) + таблиця[i, j1] * s
    верх = таблиця[i + 1, j0] * (1 - s) + таблиця[i + 1, j1] * s
    return низ * (1 - t) + верх * t


def звірити_вузол(завдання):
    """Прямий образ оберненої точки; відхил > порогу уточнення — Ньютон у (C·cos, C·sin, V).

    Чому так: лінійне обернення на тетраедрах біля білого й у насичених жовтих гне сам Lab
    (кубічний корінь Z); прямий образ — той самий ланцюжок, тож уточнена точка точна до його похибки."""
    import numpy as np
    lab, H, V, C = завдання
    ціль = np.array(lab)

    def образ(u):
        x, y, v = u
        c = math.hypot(x, y)
        h = (math.degrees(math.atan2(y, x)) / 3.6) % 100
        h = h + 100 if h < 1 else h
        if c < 1e-9:
            return None
        точка = прямий(h, v, c)
        return None if точка is None else np.array(точка)

    кут = 2 * math.pi * H / 100
    u = np.array([C * math.cos(кут), C * math.sin(кут), V])
    поточне = образ(u)
    if поточне is None:
        return (H, V, C, math.inf, 0)
    відхил = float(np.linalg.norm(поточне - ціль))
    кроків = 0
    while відхил > РЕЄСТР["поріг_уточнення"]["val"] and кроків < 8:
        кроків += 1
        Я = np.zeros((3, 3))
        for к in range(3):
            д = np.zeros(3)
            д[к] = 1e-4
            зсунуте = образ(u + д)
            if зсунуте is None:
                return (H, V, C, відхил, кроків)
            Я[:, к] = (зсунуте - поточне) / 1e-4
        try:
            крок = np.linalg.solve(Я, ціль - поточне)
        except np.linalg.LinAlgError:
            break
        нове_u, нове = u + крок, None
        for _ in range(6):
            нове = образ(нове_u)
            if нове is not None and np.linalg.norm(нове - ціль) < відхил:
                break
            крок = крок / 2
            нове_u, нове = u + крок, None
        if нове is None:
            break
        u, поточне, відхил = нове_u, нове, float(np.linalg.norm(нове - ціль))
    c = math.hypot(u[0], u[1])
    h = (math.degrees(math.atan2(u[1], u[0])) / 3.6) % 100
    return (h + 100 if h < 1 else h, float(u[2]), c, відхил, кроків)


def звірити(вузли, H, V, C, індекси):
    """Звіряє (і за потреби уточнює) обернення в пулі: H, V, C, відхил ΔLab76, кроки Ньютона."""
    завдання = [(tuple(вузли[і]), float(H[і]), float(V[і]), float(C[і])) for і in індекси]
    with multiprocessing.Pool(initializer=_робітник_старт) as пул:
        return пул.map(звірити_вузол, завдання, chunksize=256)


def межові(сітка, поле):
    """Вузли поля, у сусідстві 3×3×3 яких мітки різні (межа сімей чи краю даних): лише там похибка обернення
    може змінити мітку, всередині області сусіди з тією самою міткою її не змінюють."""
    from scipy.ndimage import maximum_filter, minimum_filter
    return поле & (maximum_filter(сітка, size=3, mode="nearest") != minimum_filter(сітка, size=3, mode="nearest"))


def поза_шкалою(сітка, поле, V):
    """Вузли за кінцями шкали світлоти: без даних і світліші за найсвітліший вузол з даними свого стовпця (a, b),
    коли той над останнім рівнем Colour (точки V 10), чи темніші за найтемніший, коли той під першим (V < 1).

    Чому так: світліше за біле й темніше за чорне кольорів нема (рішення менеджера 05.11, паспорт Річ-колір-межі):
    на шарах L* 100 і 0 є лише біле й чорне, а точки V 10 і V 0.2 лежать за адаптацією Bradford не на одному L*,
    тож вузли кінцевих шарів з хромою виходять поза оболонку даних. Це не межа з сусідньою сім'єю й не брак даних —
    модуль частку ядра там не лічить. Порожнина стовпця між вузлами з даними лишається «даних нема»."""
    import numpy as np
    рівні = значення_V()
    дані = сітка < ПОЗА_ШКАЛОЮ
    V_сітки = np.full(сітка.shape, np.nan)
    V_сітки[поле] = V
    nL = сітка.shape[0]
    верх = nL - 1 - np.argmax(дані[::-1], axis=0)
    низ = np.argmax(дані, axis=0)
    V_верху = np.take_along_axis(V_сітки, верх[None], 0)[0]
    V_низу = np.take_along_axis(V_сітки, низ[None], 0)[0]
    шар = np.arange(nL)[:, None, None]
    return (~дані & дані.any(axis=0)[None]
            & (((шар > верх[None]) & (V_верху[None] > рівні[-1])) | ((шар < низ[None]) & (V_низу[None] < рівні[0]))))


def породити(кеш=None):
    """Решітка міток сімей, статистика похибки й центри тону сімей для відносної температури.

    Прямим образом звіряємо кожен вузол біля межі міток (повторно, доки звірка зсуває межу) і випадкову пробу
    вузлів усередині областей: повна звірка мільйона вузлів (~5 мс прямого образу) не вміщалась у сесію."""
    import numpy as np
    import колір_тон as КТ
    точки, межа = вибірка(кеш)
    (L0, L1), (a0, a1), (b0, b1) = коробка()
    L, a, b = np.meshgrid(np.arange(L0, L1 + 1), np.arange(a0, a1 + 1), np.arange(b0, b1 + 1), indexing="ij")
    сітка = np.full(L.shape, НЕМА, dtype=np.uint8)
    поле = у_полі_sRGB(L, a, b)
    вузли = np.column_stack([L[поле], a[поле], b[поле]]).astype(float)
    H, V, C = обернути(точки, вузли)
    сім_ї, клітинки = клітинки_сімей()
    # Темна смуга V < 1 — лінійно між точками джерела (межа C — сама оболонка цих точок), вище — межа стовпців
    # (над V 9 — між V 9 і точками V 10). Прямим образом Colour звіряємо лише 1 ≤ V ≤ 9: поза цим він не renotation.
    темні = np.isfinite(V) & (V < 1.0)
    є = np.isfinite(V) & (V >= 0.0) & (темні | (C <= межа_C(np.nan_to_num(H, nan=1.0), np.nan_to_num(V, nan=1.0), межа) + 1e-9))
    # Хрома нижче 10⁻⁹ — нейтраль: її Lab не залежить від тону, звіряти нічого.
    нейтральні = є & (C < 1e-9)
    відхил = np.full(вузли.shape[0], np.nan)
    звірено = np.zeros(вузли.shape[0], dtype=bool)
    уточнено = 0
    межа_відхилу = РЕЄСТР["межа_звороту"]["val"]

    def позначити():
        блок, сім_я = мітки(np.nan_to_num(H, nan=1.0), np.nan_to_num(V), np.nan_to_num(C), клітинки)
        сім_я[~є] = НЕМА
        сітка[поле] = сім_я
        return блок, сім_я

    def звірити_індекси(індекси):
        nonlocal уточнено
        вихід = np.array(звірити(вузли, H, V, C, індекси))
        H[індекси], V[індекси], C[індекси] = вихід[:, 0], вихід[:, 1], вихід[:, 2]
        відхил[індекси] = вихід[:, 3]
        звірено[індекси] = True
        уточнено += int((вихід[:, 4] > 0).sum())
        є[індекси] &= вихід[:, 3] <= межа_відхилу

    блок, сім_я = позначити()
    раунди = []
    while True:
        кандидати = межові(сітка, поле)[поле] & є & ~нейтральні & ~звірено & (V >= 1.0) & (V <= 9.0)
        індекси = np.flatnonzero(кандидати)
        if not індекси.size or len(раунди) >= 8:
            break
        звірити_індекси(індекси)
        блок, сім_я = позначити()
        раунди.append(int(індекси.size))
        print("раунд звірки біля меж:", раунди[-1], file=sys.stderr, flush=True)
    поза = поза_шкалою(сітка, поле, V)
    сітка[поза] = ПОЗА_ШКАЛОЮ
    # Проба всередині: вузли далеко від меж міток; звірка — лише для звіту, мітки не змінює.
    всередині = np.flatnonzero(є & ~нейтральні & ~звірено & (V >= 1.0) & (V <= 9.0))
    генератор = np.random.default_rng(20261105)
    проба = генератор.choice(всередині, size=min(РЕЄСТР["проба_всередині"]["val"], всередині.size), replace=False)
    проба_вихід = np.array(звірити(вузли, H, V, C, проба))
    пробні_мітки = мітки(проба_вихід[:, 0], проба_вихід[:, 1], проба_вихід[:, 2], клітинки)[1]
    проба_добра = проба_вихід[:, 3] <= межа_відхилу
    змінили = int((проба_добра & (пробні_мітки != сім_я[проба])).sum())
    без_клітинки = int((є & (блок == 0)).sum())
    прийняті = відхил[звірено & є]
    центри = центри_тону(вузли, сім_я, сім_ї, КТ)
    сирі = сітка.tobytes()
    дані = base64.b85encode(zlib.compress(сирі, 9)).decode("ascii")
    return {
        "сім_ї": сім_ї, "коробка": [[L0, L1], [a0, a1], [b0, b1]], "крок": РЕЄСТР["крок_решітки"]["val"],
        "дані": дані, "sha256_сирих": hashlib.sha256(сирі).hexdigest(), "центри_θ": центри,
        "лічба": {
            "вибірка_HVC": int(точки.shape[0]), "вузлів_у_полі_sRGB": int(поле.sum()),
            "з_даними": int((поле & (сітка < ПОЗА_ШКАЛОЮ)).sum()), "без_даних": int((поле & (сітка == НЕМА)).sum()),
            "поза_шкалою_в_полі": int((поле & поза).sum()), "поза_шкалою_разом": int(поза.sum()),
            "нейтральних": int(нейтральні.sum()), "темна_смуга_без_звірки": int((є & (V < 1.0)).sum()),
            "світла_смуга_без_звірки": int((є & (V > 9.0)).sum()),
            "звірено_біля_меж_за_раундами": раунди,
            "звірено_разом": int(звірено.sum()), "уточнено_ньютоном": уточнено,
            "відкинуто_зворотом": int((звірено & ~є).sum()), "без_клітинки": без_клітинки,
            "відхил_звірених_прийнятих_p50": float(np.percentile(прийняті, 50)),
            "відхил_звірених_прийнятих_p99": float(np.percentile(прийняті, 99)),
            "відхил_звірених_прийнятих_макс": float(прийняті.max(initial=0)),
            "проба_всередині": int(проба.size),
            "проба_відхил_p99": float(np.percentile(проба_вихід[:, 3], 99)),
            "проба_відхил_макс_скінченний": float(np.nanmax(np.where(np.isfinite(проба_вихід[:, 3]), проба_вихід[:, 3], np.nan))),
            "проба_понад_межу": int((~проба_добра).sum()), "проба_змінили_б_мітку": змінили,
            "за_сім_ями": {к: int((сітка == і).sum()) for і, к in enumerate(сім_ї)},
            "блоків_у_решітці": int(np.unique(блок[є]).size),
        },
    }


def центри_тону(вузли, сім_я, сім_ї, КТ):
    """Круговий центр θ кожної барвної сім'ї: середнє за вузлами з хромою ≥ 1, вага — хрома."""
    import numpy as np
    центри = {}
    C = np.hypot(вузли[:, 1], вузли[:, 2])
    h = np.degrees(np.arctan2(вузли[:, 2], вузли[:, 1])) % 360
    for і, код in enumerate(сім_ї):
        if код == "achromatic":
            continue
        м = (сім_я == і) & (C >= 1)
        θ = np.radians([КТ.у_коло_художника(float(x)) for x in h[м]])
        центри[код] = round(float(np.degrees(np.arctan2((C[м] * np.sin(θ)).sum(), (C[м] * np.cos(θ)).sum())) % 360), 1)
    return центри


def блок_модуля(артефакт):
    """Текст згенерованого блока `колір_тон.py`: дані решітки рядками по 4000 символів."""
    д = артефакт["дані"]
    частини = "\n".join('    "%s"' % д[i:i + 4000] for i in range(0, len(д), 4000))
    return (f"{ПОЧАТОК}\n_РЕШІТКА_СІМЕЙ = {{\n"
            f'    "сім_ї": {tuple(артефакт["сім_ї"])!r},\n'
            f'    "коробка": {tuple(tuple(x) for x in артефакт["коробка"])!r},\n'
            f'    "sha256": "{артефакт["sha256_сирих"]}",\n'
            f'    "поза_шкалою": {ПОЗА_ШКАЛОЮ},\n'
            f'    "центри_θ": {артефакт["центри_θ"]!r},\n'
            f'}}\n_РЕШІТКА_ДАНІ = (\n{частини}\n)\n{КІНЕЦЬ}')


def вписати(блок):
    """Замінює згенерований блок у `колір_тон.py` (між позначками) чи дописує його в кінець."""
    текст = МОДУЛЬ.read_text(encoding="utf-8")
    if ПОЧАТОК in текст:
        до, решта = текст.split(ПОЧАТОК, 1)
        текст = до + блок + решта.split(КІНЕЦЬ, 1)[1]
    else:
        текст = текст.rstrip("\n") + "\n\n\n" + блок + "\n"
    МОДУЛЬ.write_text(текст, encoding="utf-8")


