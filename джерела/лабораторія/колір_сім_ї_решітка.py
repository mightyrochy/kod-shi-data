def прямий(H, V, C):
    """Lab точки H/V/C або None, коли renotation її не визначає (поза даними)."""
    try:
        return _ПЕРЕТВОРИТИ(H, V, C)[0]
    except (ValueError, AssertionError, RuntimeError, IndexError, KeyError):
        return None


def стовпець(HV):
    """Усі точки стовпця (H, V) від C = крок до першої відмови renotation."""
    H, V = HV
    крок = крок_C(V)
    точки, C = [], крок
    while C <= 50:
        lab = прямий(H, V, C)
        if lab is None:
            break
        точки.append((H, V, C) + tuple(lab))
        C += крок
    return точки


def крок_C(V):
    """Крок хроми стовпця за його V (реєстр «крок_C»: останній поріг V, не вищий за V)."""
    return [крок for поріг, крок in РЕЄСТР["крок_C"]["val"] if V >= поріг][-1]


def нейтраль(V, бібліотека):
    """Lab нейтралі N V: x, y освітлювача C, після Bradford — білий D65, отже a* = b* = 0."""
    Y = float(бібліотека.notation.munsell_colour_to_xyY(f"N{V:.12g}")[2])
    return (V, from_xyz(0.95047 * Y, Y, 1.08883 * Y)[0])


def у_lab(xyY):
    """Lab точки renotation xyY (освітлювач C) тим самим ланцюжком, що й `ОСНОВА.зробити_перетворення`;
    None — уявна точка (XYZ < 0)."""
    x, y, Y = xyY
    if y <= 0:
        return None
    xyz = (x * Y / y, Y, (1 - x - y) * Y / y)
    if min(xyz) < 0:
        return None
    від = ОСНОВА.множ(ОСНОВА.BRADFORD, ОСНОВА.БІЛІ["C"])
    до = ОСНОВА.множ(ОСНОВА.BRADFORD, ОСНОВА.БІЛІ["D65"])
    lms = ОСНОВА.множ(ОСНОВА.BRADFORD, xyz)
    return tuple(ОСНОВА.from_xyz(*ОСНОВА.множ(ОСНОВА.BRADFORD_ОБЕРНЕНА,
                                              tuple(lms[i] * до[i] / від[i] for i in range(3)))))


def точки_набору(бібліотека, рівні):
    """Точки renotation all.dat на рівнях V (H, V, C, L, a, b): xy з набору, Y нейтралі того самого V.

    Чому так: Colour інтерполює renotation лише між цілими V від 1 до 9, а в наборі all.dat є рівні 0.2–0.8
    і 10: без перших чорне (L* < 10.6) лишалось без сім'ї, без других над V 9 Colour веде xy лінійно до N10 і
    стискає хрому біля білого. Звірки прямим образом тут нема — це самі точки джерела."""
    from colour.notation.datasets.munsell import MUNSELL_COLOURS_ALL
    from colour.notation.munsell import hue_to_ASTM_hue, munsell_colour_to_munsell_specification
    import numpy as np
    рядки = []
    for (тон, V, C), xyY in MUNSELL_COLOURS_ALL:
        if V not in рівні:
            continue
        hue, _, _, код = munsell_colour_to_munsell_specification(f"{тон} {V:g}/{C:g}")
        H = float(hue_to_ASTM_hue(np.array([hue, код])))
        H = H + 100 if H < 1 else H
        Y = float(бібліотека.notation.munsell_colour_to_xyY(f"N{V:g}")[2])
        lab = у_lab((float(xyY[0]), float(xyY[1]), Y))
        if lab is not None:
            рядки.append((H, float(V), float(C)) + lab)
    return рядки


