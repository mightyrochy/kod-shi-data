def ролі_вузлів(вузли, H, V, C, блок, тон, незвірені, поле, сім_ї, клітинки):
    """Роль нейтралі K-COL-06 у барвній сім'ї кожного вузла: 0 — нема, 1… — номер ролі `ролі_нейтралі` + 1.

    Роль — блок ISCC-NBS вузла серед блоків ролі й сім'я тону вузла — сім'я ролі (нейві — синя, кремовий —
    жовта): решту частки вузла модуль і так лічить ахроматичній. Межа ролі лежить усередині сім'ї, тож звірка біля
    меж сімей її не торкнулась: вузли біля межі ролі звіряємо прямим образом окремо — мітки сімей це не змінює."""
    import numpy as np
    ролі_р = РЕЄСТР["ролі_нейтралі"]["val"]
    def позначити(блоки, тони):
        р = np.zeros(блоки.shape, dtype=np.uint8)
        for і, (сім_я, номери) in enumerate(ролі_р.values()):
            р[np.isin(блоки, номери) & (тони == сім_ї.index(сім_я))] = і + 1
        return р
    роль = позначити(блок, тон)
    сітка = np.zeros(поле.shape, dtype=np.uint8)
    сітка[поле] = роль
    індекси = np.flatnonzero(межові(сітка, поле)[поле] & незвірені & (V >= 1.0) & (V <= 9.0))
    вихід = np.array(звірити(вузли, H, V, C, індекси)).reshape(-1, 5)
    добрі = вихід[:, 3] <= РЕЄСТР["межа_звороту"]["val"]
    нові = мітки(вихід[:, 0], вихід[:, 1], вихід[:, 2], клітинки)[0]
    стара = роль[індекси].copy()
    роль[індекси[добрі]] = позначити(нові[добрі], тон[індекси[добрі]])
    сітка[поле] = роль
    return сітка, роль, {"звірено_біля_меж_ролей": int(індекси.size), "змінили_роль": int((роль[індекси] != стара).sum()),
                         **{к: int((сітка == і + 1).sum()) for і, к in enumerate(ролі_р)}}


def стеля_нейтралі(вузли, сім_я, тон, частка, роль, сім_ї):
    """Найбільша C* вузла, більша частина якого — нейтраль K-COL-06 (сім'я тону — сім'я нейтралі, роль блоку чи
    частка тону менша за половину; вузол спірного блоку — роль «невідомо», не нейтраль, хіба тону в ньому менше
    половини): обвідна, яка лише окреслює вікно нейтральної ролі; членство судить ядро модуля."""
    import numpy as np
    рівні = РЕЄСТР["рівні_воріт"]["val"]
    нейтральні = [сім_ї.index(к) for к in РЕЄСТР["сім_ї_нейтралі"]["val"]]
    дані = сім_я < len(сім_ї)
    ролі_р = list(РЕЄСТР["ролі_нейтралі"]["val"])
    спірна = np.isin(роль, [ролі_р.index(к) + 1 for к in РОЛІ_НЕВІДОМО])
    нейтраль = дані & ((np.isin(тон, нейтральні) & ~спірна) | ((роль > 0) & ~спірна) | (частка < (рівні - 1) / 2.0))
    return round(float(np.hypot(вузли[нейтраль, 1], вузли[нейтраль, 2]).max()), 1)


def центри_тону(вузли, сім_я, сім_ї, КТ):
    """Круговий центр θ кожної барвної сім'ї: середнє за вузлами з хромою ≥ 1, вага — хрома."""
    import numpy as np
    центри = {}
    C = np.hypot(вузли[:, 1], вузли[:, 2])
    h = np.degrees(np.arctan2(вузли[:, 2], вузли[:, 1])) % 360
    for і, код in enumerate(сім_ї):
        if код == "achromatic":
            continue
        м = (сім_я == і) & (C >= 1)
        θ = np.radians([КТ.у_коло_художника(float(x)) for x in h[м]])
        центри[код] = round(float(np.degrees(np.arctan2((C[м] * np.sin(θ)).sum(), (C[м] * np.cos(θ)).sum())) % 360), 1)
    return центри


def блок_модуля(артефакт):
    """Текст згенерованого блока `колір_тон.py`: дані решітки сімей і решітки ролей рядками по 4000 символів."""
    д = артефакт["дані"]
    частини = "\n".join('    "%s"' % д[i:i + 4000] for i in range(0, len(д), 4000))
    р = артефакт["дані_ролей"]
    частини_ролей = "\n".join('    "%s"' % р[i:i + 4000] for i in range(0, len(р), 4000))
    return (f"{ПОЧАТОК}\n_РЕШІТКА_СІМЕЙ = {{\n"
            f'    "сім_ї": {tuple(артефакт["сім_ї"])!r},\n'
            f'    "коробка": {tuple(tuple(x) for x in артефакт["коробка"])!r},\n'
            f'    "sha256": "{артефакт["sha256_сирих"]}",\n'
            f'    "поза_шкалою": {ПОЗА_ШКАЛОЮ},\n'
            f'    "рівні_воріт": {РЕЄСТР["рівні_воріт"]["val"]},\n'
            f'    "центри_θ": {артефакт["центри_θ"]!r},\n'
            f'}}\n_РОЛІ_НЕЙТРАЛІ = {{\n'
            f'    "сім_ї": {tuple(артефакт["сім_ї_нейтралі"])!r},\n'
            f'    "ролі": {tuple(артефакт["ролі"])!r},\n'
            f'    "сім_ї_ролей": {tuple(артефакт["сім_ї_ролей"])!r},\n'
            f'    "стеля": {артефакт["стеля_нейтралі"]!r},\n'
            f'    "sha256": "{артефакт["sha256_ролей"]}",\n'
            f'}}\n_РЕШІТКА_ДАНІ = (\n{частини}\n)\n'
            f'_РЕШІТКА_РОЛЕЙ = (\n{частини_ролей}\n)\n{КІНЕЦЬ}')


def вписати(блок):
    """Замінює згенерований блок у `колір_тон.py` (між позначками) чи дописує його в кінець."""
    текст = МОДУЛЬ.read_text(encoding="utf-8")
    if ПОЧАТОК in текст:
        до, решта = текст.split(ПОЧАТОК, 1)
        текст = до + блок + решта.split(КІНЕЦЬ, 1)[1]
    else:
        текст = текст.rstrip("\n") + "\n\n\n" + блок + "\n"
    МОДУЛЬ.write_text(текст, encoding="utf-8")


