def рід_речі(річ):
    """Рід тканини для конкретної речі: спершу ВИМІР (поле `текстура` з фіду),
    потім дефолт крою, потім невідомо.

    Порядок навмисний і його не можна перевертати: назва крою — конвенція, склад
    із фіду — факт. Крій, що «зазвичай трикотажний», у конкретному SKU може бути
    тканим, і саме такий SKU і є той, що не застібається."""
    if річ.get("рід_тканини_слово"):
        return річ["рід_тканини_слово"], "слово назви (verify.рід_зі_слова, класи виробника)"
    т = рід_тканини(річ.get("текстура"))
    if т: return т, "вимір (поле `текстура` з фіду)"
    р = рід_за_кроєм(O.крій_речі(річ) if isinstance(річ, dict) else річ)
    if р == "обидва": return None, ("крій «%s» буває і тканим, і трикотажним — рід не "
                                    "виводиться з назви" % O.крій_речі(річ))
    if р: return р, "дефолт крою (не вимір): крій «%s» буває лише таким" % O.крій_речі(річ)
    return None, "ні текстури, ні відомого крою"

