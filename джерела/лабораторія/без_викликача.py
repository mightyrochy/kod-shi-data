def near_face(pixels, face_mask, радіусів=1.0):
    """ВИМІРЯНА приобличчева вага: частка видимих пікселів речі в межах
    `радіусів` висот голови від ЦЕНТРА обличчя плюс півголови (тобто ≈ одна висота
    голови від краю обличчя — так корпус і формулює приобличчеву зону). Раніше це теж було число зі словника
    (верх .90, сумка .10), хоча воно залежить від довжини й посадки речі:
    крокований топ і туніка дають різну частку, шарф — майже одиницю."""
    h = голова(face_mask)
    if not h or not pixels: return None
    R = радіусів * h
    fx = [p[0] for p in face_mask]; fy = [p[1] for p in face_mask]
    cx, cy = (min(fx)+max(fx))/2, (min(fy)+max(fy))/2
    близькі = sum(1 for (x, y) in pixels if math.hypot(x-cx, y-cy) <= R + h/2)
    return round(близькі/len(pixels), 3)

