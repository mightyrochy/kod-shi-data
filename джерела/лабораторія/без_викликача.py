def з_тілом(г, T, intent="conventional"):
    """Один граф на образ І тіло. Ребра тілесного гіперграфа (hypergraph.ребра —
    смуги прилягання, якір об'єму, одна лінія, мінімум носіння) додаються до ребер
    образу з тими самими полями. Вони не залежать від речей, тож у пулі це
    резонанс (не ключ), але в інцидентності вони — ті самі вузли зон тіла, що й
    у ребер образу: «талія» тепер несе і K-FIT-03 речі, і смугу прилягання тіла
    в одному числі. До 28.08.2026 це були два об'єкти в двох модулях."""
    if T is None: return г
    try:
        import hypergraph as ГГ
        пр = ГГ.простір(T, intent=intent, сітка="крої")
        тіл = ГГ.ребра(T, пр, intent)
    except Exception:
        return г
    ребра = list(г["ребра"])
    for р in тіл:
        # ребра тіла лягають лише на ЗОНИ ТІЛА: вони не залежать від речей і не
        # мають права зсувати вузол напруги слотів (виміряно: інакше «взуття» → «верх»)
        вузли = sorted(set(u for u in (р.get("вузли") or []) if u in ЗОНИ_ТІЛА) or [ЛЮДИНА])
        ребра.append(dict(ід="тіло:%s" % р.get("ід"), правило=р.get("джерело") or ("тіло:%s" % р.get("ід")),
                          вузли=вузли, напруга=float(р.get("напруга") or 0.0), регістр="тіло",
                          блокує=False, суть=str(р.get("рядок") or р.get("ід") or "")[:120], тіло=True))
    вузли = {}
    for р in ребра:
        for u in р["вузли"]:
            в = вузли.setdefault(u, dict(вузол=u, ребер=0, напруга=0.0, ребра=[]))
            в["ребер"] += 1; в["напруга"] += р["напруга"] / max(1, len(р["вузли"])); в["ребра"].append(р["правило"])
    for в in вузли.values(): в["напруга"] = round(в["напруга"], 3)
    return dict(ребра=ребра, вузли=sorted(вузли.values(), key=lambda в: (-в["напруга"], -в["ребер"], в["вузол"])),
                ребер_тіла=len(тіл))

