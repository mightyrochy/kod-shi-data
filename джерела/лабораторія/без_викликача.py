def зона_світлоти(F, intent="conventional"):
    """ЛЮДИНА — ЗОНА В ПРОСТОРІ ЗНАЧЕНЬ, А НЕ ТОЧКА. Тут це буквально.

    ДРУГА ПОМИЛКА ЦІЄЇ ФУНКЦІЇ, ЗНОВУ ПІЙМАНА ВИМІРОМ, ЗНОВУ НА РЕАЛЬНОМУ
    ПРОФІЛІ. Попередня версія брала `value_gap` (перепад волосся↔шкіра) як
    ЦІЛЬОВУ ВІДСТАНЬ основи від шкіри. На світлій блондинці з фото це дало
    `цільовий_перепад = 0.5 L*`: її волосся (62.5 / 78.4 / 88.1, середнє 76.3)
    майже тотожне шкірі (75.8), тож перепад чесно виміряний як 0.5 — і правило
    вимагало вдягнути її в колір її ж обличчя. Наслідок на екрані: беж (L 74)
    діставав 0.78, а все інше валилось у 0.2–0.4, включно з тим, що вона сама
    обрала. Перепад людини — це вимір ЛЮДИНИ; перетворювати його на цільову
    відстань ТКАНИНИ від обличчя нічим не підперто, і я це вигадав.

    ЩО ЗАМІСТЬ. Зона світлоти особи = [min, max] по шкірі й УСІХ пасмах
    волосся. Основа всередині зони не сперечається з обличчям, бо така
    світлота на людині вже є. Поза зоною бал спадає за один крок Value.
    Це та сама архітектура, що й скрізь у проєкті: людина як ЗОНА в просторі
    значень, а не мітка. Ширина зони при цьому сама несе контраст — у
    низькоконтрастної вона вузька, у висококонтрастної широка, і додаткової
    константи не потрібно.

    ОЧІ НЕ ВХОДЯТЬ. Та сама підстава, що в `outfit.контраст_особи`: площа
    мала, і темні очі робили б попелясту блондинку темною.

    ПІД STATEMENT ЗОНА ШИРШАЄ на крок Value з кожного боку: мета не «лестити
    обличчю», і вихід за власну світлоту тут — інструмент, а не помилка.
    """
    L = []
    for k, v in (F or {}).items():
        if k.startswith("_") or not isinstance(v, dict):
            continue
        if k == "шкіра" or k.startswith("волосся"):
            if v.get("L") is not None:
                L.append(float(v["L"]))
    if not L:
        return 40.0, 80.0
    низ, верх = min(L), max(L)
    if (intent or "conventional") != "conventional":
        низ, верх = низ - КРОК_V_L, верх + КРОК_V_L
    return низ, верх

