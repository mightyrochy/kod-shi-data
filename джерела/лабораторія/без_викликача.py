# Дві функції ядра, які СТАЛИ «ніхто» цією ж сесією: їхніх єдиних викликачів —
# `bridge._згода_зчитувань_шкіри` (жив під ендпойнтом `кольори`) і
# `pipeline.пакет_пояснення` (жив під ендпойнтом `пояснення`) — знесено разом із
# самими ендпойнтами, бо тих не кликав ніхто. Правило те саме, що для десятьох
# вище: у ядрі «ніхто» = 0, а знесення — окреме рішення власника, не наслідок
# прибирання. Тут вони не гниють мовчки: перша — єдина реалізація R-PC-09
# (шкіра↔шкіра з допуском, що масштабується світлотою), і вернути її в ядро
# коштує рівно одного викликача.

def та_сама_шкіра(lab1, lab2, L_шкіри=None, база=3.0):
    """same_colour для пари ШКІРА↔ШКІРА (два зчитування обличчя однієї людини).
    Ніколи не для річ↔річ: там працює R-COL-11 (de00_тканина)."""
    допуск, м, чому = допуск_шкіри(L_шкіри if L_шкіри is not None else
                                   (lab1[0] + lab2[0]) / 2.0, база)
    d = de00(lab1, lab2)
    return dict(same=d <= допуск, dE00=round(d, 2), допуск=допуск, множник=м,
                чому=чому,
                нота="ΔE00 надійна лише для малих різниць; допуск — підлога, не "
                     "повне виправлення нерівності (R-PC-09)")


