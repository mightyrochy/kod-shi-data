def рядок_вузла_словами(в, г, скільки=2):
    """Те саме для МОДЕЛІ: без ID правил — лише суть ребер, що навантажують вузол.
    Модель не має бачити правил (принцип: код фільтрує, модель компонує)."""
    if not в: return None
    ребра = sorted([р for р in г["ребра"] if в["вузол"] in р["вузли"] and р["напруга"] > 0],
                   key=lambda р: -р["напруга"])[:скільки]
    суті = "; ".join(р["суть"].split(" — ")[0].split(":")[0] for р in ребра if р["суть"])
    # СИЛА ЙДЕ В МОВУ. Виміряно 28.08 після того, як питання перестали тиснути: у
    # «вечір 22°» вузол «взуття» мав 0.05 з одного hint «виріз взуття тут не вирішує
    # нічого» — і пакет казав моделі «тут сходиться найбільше умов, міняй це».
    # Слова напруги — ті самі, що в hypergraph.словами (одна шкала для тіла й образу).
    from hypergraph import словами as _сл
    return "«%s» — тут %s%s" % (в["вузол"], _сл(в["напруга"]) if в["напруга"] < 0.35 else "сходиться найбільше умов",
                                 (": " + суті) if суті else "")
