def _максимум_у_вікні(проф, лоу, хай):
    """Максимум кусково-лінійної функції на відрізку досягається у вершині або на кінці —
    тому перебираються рівні всередині вікна плюс обидва кінці. Без сканування сіткою:
    сітка дала б залежність вердикту від кроку сітки."""
    точки = [лоу, хай] + [y for _, y, _ in проф if лоу < y < хай]
    best = max(точки, key=lambda y: ширина_на(проф, y))
    return best, ширина_на(проф, best)

