# -*- coding: utf-8 -*-
"""ID ПРАВИЛА — одна відповідь на питання, яке п'ять приладів питали по-своєму.

ЧОМУ ЦЕЙ ФАЙЛ ІСНУЄ. Шаблон ID був списаний п'ять разів, і жодні дві копії не
збігались:

    відбиток.py     ^[KRPE]-[A-ZА-Я0-9]{2,5}-\\d{2}[a-zа-я]?$
    правила.py      \\b([KRPE]-[A-ZА-Я0-9]{2,5}-\\d{2}[a-zа-я]?)\\b
    gate_reach.py   \\b([KRE]-[A-ZА-Я0-9]{2,5}-\\d{2}[a-zа-я]?)\\b
    gate_reach.py   \\b([KR]-[A-ZА-Я0-9]{2,5}-\\d{2}[a-zа-я]?)\\b   (цілі образів)
    корпус.py       \\b([KRE]-[A-ZА-Я0-9]{2,5}-\\d{2}[a-zа-я]?)\\b
    outfit.py       ([KRE]-[A-Z0-9]{2,5}-\\d{2})                    (вбудований)

Розбіжність не косметична, і її вже ловили руками: `gate_reach` мав `[KR]` там,
де `корпус` мав `[KRE]`, і два читачі одного корпусу давали різні знаменники в
двох звітах ПРО ОДНЕ Й ТЕ САМЕ. Коментар над одним із шаблонів каже це прямо:
«розбіжність — рівно 1 код (`K-SYS-07a`), і її ніхто не бачив». Один код —
випадок; п'ять копій одного шаблону — механізм, який видасть наступний.

ЧОГО ЖОДНА З КОПІЙ НЕ ВМІЛА. Коди, вигадані самим кодом, мають хвіст не з цифр
(`K-COL-CONF`, `K-COL-JOIN`, `R-LNG-UA`), а суфіксні варіанти правила — хвіст із
однієї літери (`K-COL-04-M`, `K-CRA-07-N`, `K-MAT-04-L`). Для `\\d{2}` перших не
існувало взагалі, а другі мовчки різались до бази, і `K-COL-04-M` був невідрізненний
від `K-COL-04`. Тут і те, й те: суфікс ВИДНО (`суфікс`), і його можна звести до
бази (`база`) — рахувати варіанти окремо, а приписувати правилу.

ЧОГО ЦЕЙ ФАЙЛ НЕ РОБИТЬ. Не каже, чи ID означений у корпусі (це `корпус`), чи
він виконується (це `gate_reach`), чи він узагалі правило, а не збіг літер у
чужому тексті. Він каже лише, ЯК виглядає ID і як розібрати його на частини.
"""
import re

# ── КАНОНІЧНИЙ ШАБЛОН ────────────────────────────────────────────────
# Група 1 — БАЗА (правило), група 2 — СУФІКС варіанта або None.
#   [KRPE]      K/R — корпус, P — провенанс палітри, E — зарезервовано.
#               `P` і `E` ловимо навмисно: код цитує P-PRT-01/02, яких у темах
#               нема, і мовчазне ігнорування таких ID — рівно та сліпота, від
#               якої лікується решта приладів.
#   {2,5}       сімʼя; цифри всередині — теж (`K-P0-01` із теми-4 був невидимий
#               для шаблону без `0-9` і для гейта просто не існував).
#   A-ZА-Я      кирилиця в сімʼї допускається: теми пишуть і так.
#   \d{2}[a-z]? номер правила з можливою літерою ревізії (`K-SYS-07a`).
#   CONF|JOIN|UA власні коди коду: службові ID, які код народжує сам
#               (конфлікт ремонтів, злиття вікон, український мовний гейт).
#   -[TMLAN]    суфікс варіанта правила.
ШАБЛОН = (r'\b([KRPE]-[A-ZА-Я0-9]{2,5}-(?:\d{2}[a-zа-я]?|CONF|JOIN|UA))'
          r'(?:-([TMLAN]))?\b')
ІД = re.compile(ШАБЛОН)
# Той самий шаблон, прибитий до країв рядка: «цей рядок — рівно один ID».
ЦІЛИЙ = re.compile(r'^' + ШАБЛОН + r'$')


def усі_в_тексті(текст):
    """Список ID у порядку появи, кожен ЦІЛИЙ — разом із суфіксом, якщо він є.

    Порядок появи, а не множина: викликач, якому потрібна множина, зробить її
    сам, а викликачеві, якому потрібен ПЕРШИЙ ID опису (`gate_reach.ЦІЛЬ_ОБРАЗУ`),
    множина не годиться. Повтори не знімаються з тієї ж причини: «скільки разів
    згадано» — законне питання, і зняти дублікати дешевше, ніж їх повернути.
    """
    return [м.group(0) for м in ІД.finditer(текст or "")]


def бази_в_тексті(текст):
    """Множина БАЗ ID у тексті: суфіксні варіанти зведені до свого правила.

    Це те, що робив `set(ШАБЛОН.findall(текст))` у кожного з п'яти читачів, — і
    саме тому суфікс ніде не було видно. Тепер зведення до бази — ЯВНИЙ виклик:
    хто хоче варіанти окремо, бере `усі_в_тексті`.
    """
    return {м.group(1) for м in ІД.finditer(текст or "")}


def цілий(рядок):
    """ID, якщо рядок — рівно один ID (без хвостів), інакше None.

    Це та перевірка, яку `відбиток` робив шаблоном із `^…$`: константа в коді
    або є ID правила цілком, або не є ним взагалі. «`K-COL-06` у реченні» тут
    навмисно не проходить — для тексту є `усі_в_тексті`.
    """
    м = ЦІЛИЙ.match(рядок or "")
    return м.group(0) if м else None


def база(ід):
    """ID без суфікса варіанта: `K-COL-04-M` → `K-COL-04`. Не ID → None.

    Приймає і ID у більшому рядку (перший збіг), бо саме так його брав
    `outfit._зн`: `re.match` по значенню поля `правило`, яке буває й довшим.
    """
    м = ІД.search(ід or "")
    return м.group(1) if м else None


def суфікс(ід):
    """Літера варіанта (`M`, `N`, `L`, `T`, `A`) або None.

    None означає «варіанта нема», а не «варіант невідомий»: правило без суфікса
    — це саме правило, а не якийсь із його варіантів.
    """
    м = ІД.search(ід or "")
    return м.group(2) if м else None


def сімʼя(ід):
    """Сімʼя правила: `K-COL-04-M` → `K-COL`, `K-COL-CONF` → `K-COL`.

    Через базу, а не `rsplit` по останньому дефісу: `rsplit` на суфіксному ID
    дав би сімʼю «K-COL-04», якої не існує, і запис реєстру для неї не знайшовся
    б — тобто правило-варіант мовчки лишалось би без роду.
    """
    б = база(ід)
    return б.rsplit("-", 1)[0] if б else None


if __name__ == "__main__":
    # ID ТУТ СКЛАДАЮТЬСЯ З ЧАСТИН, А НЕ ПИШУТЬСЯ ЦІЛИМИ, І ЦЕ НЕ ХИТРІСТЬ.
    # Цей файл — модуль ЯДРА (він у замиканні продукту), і `gate_reach.з_коду`
    # сканує його як живий код. Демонстраційний рядок із цілими ID зараховував
    # би ці правила за «у виконуваному коді» — тобто ПРИКЛАД у довідці піднімав
    # би покриття корпусу. Виміряно на першій версії цього файла: два правила
    # дістали статус «код», не маючи в системі жодного емітента.
    проба = " ".join("-".join(ч) for ч in (
        ("K", "COL", "CONF"), ("K", "COL", "06", "T"), ("R", "LNG", "UA"),
        ("P", "PRT", "01"), ("K", "SYS", "07a"), ("K", "P0", "01"),
        ("K", "COL", "04", "M")))
    for і in усі_в_тексті(проба):
        print("%-12s база=%-10s суфікс=%-4s сімʼя=%s"
              % (і, база(і), суфікс(і) or "—", сімʼя(і)))
