"""Свідок кольору речі у вікні палітри."""
import outfit as O, feed
import фід_добір as _ФД     # ключі кешу частки вікна (`колір_речі`, `влучає`)
import колір_річ as _КР        # колір речі одним записом: вікно чи точка

def колір_речі(r):
    """(межі, вікно, точка, ключ вікна) кольору речі одним записом: `межі_кольору`, `вікно_речі` (лише коли межі
    є), `точка_кольору` (лише коли межі є, а вікна нема) і `фід_добір.ключ_вікна` вікна. Колір речі від вікна запиту не залежить, тож цикл
    «вікно × річ» читає його раз на річ, а не на кожне вікно: тричі на пару це було майже половиною часу
    виклику `запити` в Pyodide (наряд Збирання-запити-час, 13.11)."""
    межі = _КР.межі_кольору(r)
    if not межі:
        return межі, None, None, None
    вк = _КР.вікно_речі(r)
    if вк:
        return межі, вк, None, _ФД.ключ_вікна(вк)
    return межі, None, _КР.точка_кольору(r), None

def влучає(r, q, колір=None, ключ_q=None):
    """частка вікна (річ-зона) або точкове влучання; рядок металу — тон коду матеріалу (`feed.влучає_метал`);
    None — річ без кольору. `колір` — `колір_речі(r)`, `ключ_q` — `фід_добір.ключ_запиту(q)`, уже прочитані циклом."""
    м = feed.влучає_метал(r, q)
    if м is not None:
        return 1.0 if м else 0.0
    # П.14: lab і вікно речі народжує `фід_каталог` (трійка float або None), і
    # `None` тут уже названо рядком вище. Ковтати решту означало б віддати
    # «річ без кольору» на зламаний вимір — вони були невідрізненні.
    межі, вк, точка, кв = колір if колір is not None else колір_речі(r)
    if not межі: return None
    # ВІКНО — ЗА ПОЛЕМ `колір_не_вимір`, А НЕ ЗА ПОЛЕМ `вікно`: `вікно`
    # пише лише гілка слова крамниці, а hex і слово моделі з опису фото (452 речі пулу стенда)
    # не вимір теж — доти їх судили точкою свого hex, а суд тих самих речей — вікном слова.
    if вк:
        return feed.частка_вікна(вк, q, ключі=(кв, ключ_q if ключ_q is not None else _ФД.ключ_запиту(q)))
    return 1.0 if feed.підходить(точка, q) else 0.0
