def _поля_укладки(offer, сл):
    """Поля речі, які читає третій канал (`outer`), — з того самого оффера.

    ЧОМУ ЦЕ ІСНУЄ (Н-outer-1-076). `показ` збирав картку з id, назви, слота, фото,
    url і ціни, і `опис` будував із НЕЇ вхід третього каналу. Тобто
    `outer.перевірити` діставав річ без `тип_верхнього`, без `пояс`, без `комір` —
    а K-OUT-19 (вузол пояса тренча), K-OUT-29 (піднятий комір) і K-OUT-13 (стійка
    заміщає шарф) вмикаються рівно цими полями. ВИМІРЯНО: `канал_3["команди"]` на
    живому шляху «опис» був порожнім списком ЗАВЖДИ, на будь-якому образі.

    ПЕРЕЛІК НЕ ВИГАДАНИЙ ТУТ: це рівно те, що `feed.прогін` кладе в каталог поруч
    із типом (feed.py:2365 і 2395) — `тип_речі`, `верхні_атрибути` і
    `довжина_речі`. Друге джерело тих самих полів було б другим словником значень,
    тобто тим класом дефекту, який проєкт уже ловив.

    ОКРЕМИЙ КЛЮЧ, А НЕ ПЛОСКА КАРТКА: картка показу — те, що людина бачить очима, і
    дев'ятнадцять технічних полів у ній зробили б її нечитною. `укладка` їде поруч і
    називає себе.
    """
    if not offer:
        return {}
    import feed as _Ф
    тип = _Ф.тип_речі(offer, сл)
    a = dict(_Ф.верхні_атрибути(offer))
    рів, дж = _Ф.довжина_речі(offer, сл)
    if рів:
        a["довжина_рівень"], a["довжина_джерело"] = рів, дж
    if тип:
        a["тип"] = тип
    return a


