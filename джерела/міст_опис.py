def _поля_укладки(offer, сл):
    """Поля речі, які читає третій канал (`outer`), — з того самого оффера.

    ЧОМУ ЦЕ ІСНУЄ (Н-outer-1-076). `показ` збирав картку з id, назви, слота, фото,
    url і ціни, і `опис` будував із НЕЇ вхід третього каналу. Тобто
    `outer.перевірити` діставав річ без `тип_верхнього`, без `пояс`, без `комір` —
    а K-OUT-19 (вузол пояса тренча), K-OUT-29 (піднятий комір) і K-OUT-13 (стійка
    заміщає шарф) вмикаються рівно цими полями. ВИМІРЯНО: `канал_3["команди"]` на
    живому шляху «опис» був порожнім списком ЗАВЖДИ, на будь-якому образі.

    ПЕРЕЛІК НЕ ВИГАДАНИЙ ТУТ: це рівно те, що `feed.прогін` кладе в каталог поруч
    із типом (feed.py:2365 і 2395) — `тип_речі`, `верхні_атрибути` і
    `довжина_речі`. Друге джерело тих самих полів було б другим словником значень,
    тобто тим класом дефекту, який проєкт уже ловив.

    ОКРЕМИЙ КЛЮЧ, А НЕ ПЛОСКА КАРТКА: картка показу — те, що людина бачить очима, і
    дев'ятнадцять технічних полів у ній зробили б її нечитною. `укладка` їде поруч і
    називає себе.
    """
    if not offer:
        return {}
    import feed as _Ф
    тип = _Ф.тип_речі(offer, сл)
    a = dict(_Ф.верхні_атрибути(offer))
    рів, дж = _Ф.довжина_речі(offer, сл)
    if рів:
        a["довжина_рівень"], a["довжина_джерело"] = рів, дж
    if тип:
        a["тип"] = тип
    return a


def показ(вхід):
    """Картки речей для сторінки показу: id + усе, що людина побачить очима.

    ЧОМУ ОКРЕМИЙ ВХІД. `від_моделі` віддає речі як {id, слот, назва, hex} — цього
    досить коду і НЕ досить людині: без фото, ціни й посилання на магазин картка
    на показі порожня, а вердикт тоді міряє текст, а не річ. Фото беремо з фіду
    (`picture`) — перше, а де жнива обрали кадр, на якому річ видно цілком, там
    перший саме він (див. блок «ОБРАНИЙ КАДР ПЕРШИМ» нижче); url — той самий,
    що їде з оффером.

    ПОРУЧ ІЗ КАРТКОЮ ЇДЕ `укладка` (Н-outer-1-076) — поля, які читає третій канал.
    Вони не для ока й не для промпта; вони для `outer.перевірити`, який доти діставав
    річ, зрізану до назви.
    """
    d = _json.loads(вхід) if isinstance(вхід, str) else вхід
    import feed as _Ф, html as _html
    import назва_речі as _НР
    шлях, _ = _каталог_із(d)
    оф = _Ф.читати_yml(шлях)[0]
    за_ід = {o["id"]: o for o in оф}
    # СПІЙМАНО 29.08.2026: id у фіді — «ж-00017@gepur.com». Голий «ж-00017» без
    # магазину НЕ унікальний між магазинами (жниварка нумерує всередині магазину).
    # Тому голий префікс шукаємо, але за неоднозначності НЕ вгадуємо: картка їде
    # порожня з поміткою — інакше на показі людина судила б чужу річ.
    за_коренем = {}
    for o in оф:
        за_коренем.setdefault(str(o["id"]).split("@")[0], []).append(o)
    # ── ОБРАНИЙ КАДР ПЕРШИМ (19.09.2026, рядок 51 беклогу) ──────────────────
    # Жнива дивляться на всі фото речі й записують у `запис.фото` ТОЙ КАДР, на
    # якому річ видно цілком (`жнива_v2.py:1195`); саме його вони й описували.
    # Картка ж брала `фото[0]` фіду — на чоботях LeBERDES це підошва, і жінка
    # судила підошву замість чобота. Тому порядок фото речі тут переставляється
    # один раз, і ним користуються ОБИДВА читачі: картка (`фото`) і крок опису
    # (`фото_усі` → `bridge.опис` → `pipeline.опис_v1`), інакше модель описувала б
    # інший знімок, ніж бачить жінка.
    #   · кадр береться, ЛИШЕ коли він є серед `picture` цієї речі: чужий URL із
    #     збагачення (сестринська гілка, збій жнив) поставив би на картку чужу річ;
    #   · `_збагачення_придатне` тут не питається навмисно — воно судить СЛОВО
    #     кольору, а кадр перевіряється власним свідком (належністю до фото речі):
    #     на 1 271 записі з непридатним кольором знімок речі все одно її знімок;
    #   · речі без збагачення лишаються як були — перше фото фіду.
    # `фото_ключ` (одиниця дедуплікації дизайну, `feed.py:3121`) рахується в
    # `feed`, до цього виклику, і перестановка його не торкається.
    # 21.09.2026 (рядок 118): «є серед picture» звіряється тепер ФАЙЛОМ
    # (`_файл_фото`), а не цілим рядком, бо крамниця віддає той самий знімок у
    # різних розмірах; сам відбір див. у докстрінгу `_фото_речі`. Там-таки —
    # НАЗВАНИЙ окремий випадок «у фіді цієї крамниці власних знімків нема
    # взагалі»: тоді, і лише тоді, кадр береться, навіть якщо серед `picture`
    # його файла нема, — з двома власними межами (хост крамниці, той самий
    # поріг `СПІЛЬНЕ_ФОТО_ТОВАРІВ`).
    _зб_усе = _Ф.читати_збагачення()
    _спільні = _спільні_фото(оф)
    _хости = _хости_крамниць(оф)
    def _фото_речі(o):
        """Кадри цієї речі в тому порядку, у якому їх побачать, — `фід_фото`.

        Саме правило (порядок, відсів, запасний шлях, форма кадру) живе в
        `фід_фото.кадри_речі`: рядок 143 просив одне місце на всіх читачів,
        а замикання всередині `показ` не могло прочитати ні проба, ні вимір.
        Тут лишились тільки входи, які знає показ: словники крамниці й кадр
        жнив цієї речі.
        """
        мг = o.get("магазин") or str(o.get("id") or "").split("@")[-1]
        з = _зб_усе.get(o.get("id"))
        return кадри_речі(o, _спільні.get(мг) or {}, _хости,
                          з.get("фото") if isinstance(з, dict) else None)

    def _чому_без_фото(o):
        """Чому на картці цієї речі нема знімка — `фід_фото.чому_без_кадру`.

        Той самий доказ, що й у відсіві: другої думки про «чому нема» тут нема
        й бути не може (рядок 124). Самі стани — у докстрінгу `чому_без_кадру`.

        ТРЕТІЙ СТАН СЮДИ НЕ ЗАХОДИТЬ, І ЦЕ ВИРІШУЄ ВИКЛИКАЧ (23.09.2026, рядок
        140). Усі рядки, які віддає `чому_без_кадру`, — свідчення ПРО КРАМНИЦЮ,
        і сказати їх можна лише про річ, яку каталог знає. Коли речі в каталозі
        нема (руки 3–4 показу вигадують речі — CLAUDE.md п.1: модель без коду й
        без каталогу), крамниці й фіду в неї нема за побудовою, і «крамниця не
        дала у фід жодного знімка» — не мовчання, полагоджене рядком, а
        неправда: ані такої крамниці, ані такого фіду не існує. Тому виклик
        стоїть за умовою «річ знайдена в каталозі» (`у_каталозі` нижче), а не
        тут: функція відповідає за ПРИЧИНУ, викликач — за те, чи є про що
        свідчити.
        """
        мг = o.get("магазин") or str(o.get("id") or "").split("@")[-1]
        return чому_без_кадру(o, _спільні.get(мг) or {})

    вих = []
    # РІЧ ЖІНКИ З ФОТО (рядок 152): каталог її не знає — картка з паспорта, без крамниці,
    # ціни й посилання, а фото показ бере з телефона за `фото_ід`. Без фото — порожньо.
    import річ_з_фото as _РФ, міст_річ as _МР
    _пасп = d.get("паспорт") if isinstance(d.get("паспорт"), dict) else None
    _її = _РФ.картки_з_паспорта(_пасп, судити=(_МР.судження(d) if _РФ.закріплені((_пасп or {}).get("речі_з_фото")) else None))
    for р in (d.get("речі") or []):
        ід = р.get("id") if isinstance(р, dict) else р
        if ід in _її:
            вих.append(dict(_її[ід]))
            continue
        o = за_ід.get(ід)
        неоднозначно = False
        if o is None:
            збіги = за_коренем.get(str(ід).split("@")[0], [])
            if len(збіги) == 1:
                o = збіги[0]
            elif len(збіги) > 1:
                неоднозначно = True
        # РІЧ, ЯКОЇ КАТАЛОГ НЕ ЗНАЄ, НЕ МАЄ КРАМНИЦІ (рядок 140): про неї не
        # кажеться нічого — ні про фід, ні про спільну картинку.
        у_каталозі = o is not None
        o = o or {}
        _фф = _фото_речі(o)
        фото = _фф[0] if _фф else None
        _чм = _чому_без_фото(o) if (not _фф and у_каталозі) else None
        _сл = ((р.get("слот") if isinstance(р, dict) else None) or o.get("слот")
               or (_Ф.слот(o) if o else None))
        _укл = _поля_укладки(o, _сл)
        # ── НАЗВА ДЛЯ ЖІНКИ, А НЕ ДЛЯ ПАРСЕРА (рядок 144 дошки, 23.09.2026) ──
        # Ручний огляд каталогу куратором: на картці стояли «Other Brand»,
        # «ПАЛЬТО», «… , артикул - 16734, 【MustHave ❤️】ціна», «гладкої в&#8217;язки»,
        # «Женские широкие брюки (1, S, black, чорний)», «Уги VS000086107» і
        # «Дивіться також Коктейльна сукня…» під фото топа. `назва_речі` дає
        # людську назву, а `назва_крамниці` лишає поруч те, що написав магазин, —
        # обидва поля їдуть на картку, тож нічого не зникає мовчки.
        # ЛІНИВО Й ТІЛЬКИ ТУТ: рахунок коштує 0.21 мс на річ, а речей на картці
        # десяток; на всьому каталозі (12 405) те саме коштувало б 2.6 с у
        # `читати_yml`, тобто +58 % до читання фіду на телефоні — за поле, якого
        # не бачить ніхто, крім картки. Добір пулу й вибір слота читають `назва`
        # і не міняються ні на байт.
        _сира_назва = _html.unescape((р.get("назва") if isinstance(р, dict) else None)
                                     or o.get("назва") or "") or None
        _пн = _НР.назва_для_показу(dict(o, назва=_сира_назва)) if _сира_назва else None
        вих.append(dict(id=ід,
                        назва=(_пн["назва"] if _пн else None) or _сира_назва,
                        **({"назва_крамниці": _сира_назва,
                            "назва_джерело": ("%s (у фіді: %s)" % (_пн["джерело"], _пн["причина"]))
                                             if _пн["причина"] else "фід, почищено"}
                           if _пн and _пн["назва"] != _сира_назва else {}),
                        # слот — із запису, з оффера або з `feed.слот` (голий id без
                        # слота давав у промпт опису «річ» замість «сукня»)
                        слот=_сл,
                        # поля третього каналу (Н-outer-1-076): не для ока, для `outer`
                        **({"укладка": _укл} if _укл else {}),
                        фото=фото, урл=o.get("url"), ціна=o.get("ціна"),
                        # УСІ фото речі — для опису з фото (02.09.2026): картка
                        # показує перше, модель на кроці опису бачить усі.
                        фото_усі=_фф,
                        # ЧОМУ ЗНІМКА НЕМА — ПОЛЕМ, А НЕ МОВЧАННЯМ (рядок 124):
                        # ставиться РІВНО тоді, коли картка йде без фото, і
                        # ніколи поруч зі знімком.
                        **({"чому_без_фото": _чм} if (not _фф and _чм) else {}),
                        **({"неоднозначний_ід": True} if неоднозначно else {})))
    return _json.dumps(вих, ensure_ascii=False, default=str)


# ── СКІЛЬКИ ФОТО ЙДЕ В ОПИС ─────────────────────────────────────────────────
# Рішення власника 02.09.2026: речей — скільки в образі, фото на річ — 1–2.
# ПІСЛЯ ПРОГОНУ НА ПОВНОМУ КАТАЛОЗІ те саме правило дало 22 фото (образ із
# одинадцяти речей!), обрізалось до 20 порогом API — і виклик усе одно впав
# із HTTP 400. Тому стеля тепер НА ОБРАЗ, а не лише на річ: коли речей багато,
# кожна дістає по одному фото, а разом їх не більше `ФОТО_НА_ОБРАЗ`. Друге
# фото — розкіш, яку можна дозволити на короткому образі; перше фото кожної
# речі — необхідність, бо без нього річ описують за назвою.
ФОТО_НА_РІЧ = 2
ФОТО_НА_ОБРАЗ = 10


def опис(вхід):
    """Четвертий виклик: промпт опису ОБРАНОГО образу + адреси фото його речей.

    Вхід: {…той самий випадок…, каталог, речі: [id…], підпис?, свідомі?, номери?,
    образ?}. Вихід: {промпт (ОПИС_V1 рядком), опис (той самий обʼєкт), фото: [url…]
    у порядку, у якому вони пронумеровані в обʼєкті, речі, обрізано: скільки фото
    не ввійшло, усього_фото, канал_3}.

    НОМЕР РЕЧІ ПРИХОДИТЬ ГОТОВИМ (`номери`: id → «#12·03»). Його роздає нумерація
    ПУЛУ, а пулу на цьому кроці нема: будувати його вдруге заради кількох номерів
    означало б ще один відбір каталогу на найдорожчому виклику. Тому номери дає
    `від_моделі.вибір.номери` — там пул уже стоїть. Без них (прилади, що кличуть
    `опис` прямо: `тест_живого_шляху`, `траса_петлі`) річ називається своїм id:
    прозу модель однаково пише без нього, а `фото_не_те` резолвиться тим самим
    `_розпізнати_речі`.

    СКІЛЬКИ ФОТО (рішення власника 02.09.2026): речей — стільки, скільки в
    образі, без стелі; на одну річ — не більше `ФОТО_НА_РІЧ` (перші два з фіду:
    друге фото жниварки — зазвичай інший ракурс або деталь, третє й далі —
    повтори на моделі). Шість фото однієї сукні нічого не додають, а токени
    їдять. Поріг API у 20 зображень на запит лишається запобіжником на випадок
    образу з десятком речей: тоді спершу знімаються другі фото, і число
    обрізаних називається — це не наш ліміт, а чужий поріг, і він видимий."""
    d = _json.loads(вхід) if isinstance(вхід, str) else вхід
    d = _застосувати_паспорт(d)
    import pipeline as _PL
    речі = _json.loads(показ(d))
    # ЇЇ РІЧ БАЧИТЬСЯ ТИМ САМИМ ШЛЯХОМ, ЩО ПРИМІРЯННЯ (рядок 152): фото з телефона, не з
    # крамниці. Тут стоїть маркер `її-фото:ф1`, і показ підставляє на його місце байти
    # (блок base64), як для фото на повний зріст у приміряння. Номер фото рахується так
    # само, як для решти, тож «фото_не_те» на ній резолвиться тією самою лічбою.
    import річ_з_фото as _РФ
    for р in речі:
        if р.get("власна") and р.get("фото_ід"):
            р["фото_усі"] = [_РФ.МАРКЕР_ФОТО + str(р["фото_ід"])]
    # Перше фото КОЖНОЇ речі — не розкіш: без нього річ описують за назвою, тобто
    # рівно те, від чого цей крок і рятує. Тому стеля образу піднімається до
    # числа речей (у межах порога API), а друге фото дається лише коли влазить.
    ПОРІГ_API = min(20, max(ФОТО_НА_ОБРАЗ, len(речі)))
    _на_річ = ФОТО_НА_РІЧ if len(речі) * ФОТО_НА_РІЧ <= ПОРІГ_API else 1
    for р in речі:
        р["фото"] = list((р.get("фото_усі") or [])[:_на_річ])
    усі = sum(len(р["фото"]) for р in речі)
    обрізано = 0
    if d.get("без_фото_опису"):
        # повтор після відмови через зображення: той самий опис, без фото
        for р in речі:
            р["фото"] = []
        усі = 0
    elif усі > ПОРІГ_API:
        # спершу знімаються ДРУГІ фото (у зворотному порядку речей), лише потім перші
        k = _на_річ - 1
        while сум(речі) > ПОРІГ_API and k >= 0:
            for р in reversed(речі):
                if len(р["фото"]) > k and сум(речі) > ПОРІГ_API:
                    р["фото"].pop()
            k -= 1
        обрізано = усі - сум(речі)
    фото = [x for р in речі for x in (р.get("фото") or [])]
    _частини = d.get("частини") if isinstance(d.get("частини"), dict) else {}
    # ── ТРЕТІЙ КАНАЛ РАХУЄТЬСЯ ТУТ (07.09.2026) ──────────────────────────────
    # Команди розкладки залежать від ОБРАНИХ речей, тому раніше за цей виклик їх
    # рахувати нема з чого. `accessory.команди_розкладки` віддає опції з названими
    # компромісами (хустка: шия / сумка / зап'ясток), `outer.команди_укладки` —
    # знахідки (пояс тренча, піднятий комір). Обидві функції існували й нікуди не
    # доходили: до 07.09 `канал_3` не читав жоден модуль системи.
    _к3 = dict(опції=[], команди=[])
    # П.14 (СТАНДАРТ §4): «третій канал не має права зронити опис» було правдою
    # рівно наполовину. Порожній `_к3` уже означає «команд розкладки нема» — і
    # саме так його читає `опис_v1`. Мовчазний `except` додавав другу причину
    # тієї самої порожнечі, і вимір «канал_3 доїхав» ставав невимірюваним.
    # Вхід тут свій: обрані речі, зріст і обхвати того ж виклику моста.
    import accessory as _АК, outer as _ВШ
    # ── РІЧ ЇДЕ В КАНАЛ ЦІЛОЮ (Н-outer-1-076) ────────────────────────────
    # Доти сюди йшли п'ять полів, і `тип` із `розмір_см` серед них були порожні
    # завжди: `показ` їх не клав. `укладка` (див. `_поля_укладки`) несе рівно те,
    # що читає `outer` — тип верхнього, бортність, пояс, комір, рукав, рівень
    # довжини, оверсайз, частку вовни, простібку, fill power і вето на нього.
    # Вона йде ОСТАННЬОЮ: поле з фіду важить більше за порожнє поле картки.
    _для_к3 = [dict(dict(id=р.get("id"), слот=р.get("слот"), назва=р.get("назва"),
                         тип=р.get("тип"), розмір_см=р.get("розмір_см")),
                    **(р.get("укладка") or {}))
               for р in речі]
    # ── ТІЛО, А НЕ МОВЧАЗНИЙ None (Н-outer-1-076, крок 3) ────────────────
    # `опис` дістає `зріст` і `обхвати` тим самим пакетом, що й решта викликів
    # моста, тож тіло тут доступне — і без нього `край_см` у каналі 3 не
    # працював за побудовою. МЕЖА, названа вголос: канал 3 віддає далі лише
    # `команди`, а краї (K-OUT-03, K-OUT-04) лишаються всередині `перевірити`;
    # тіло робить їх правдивими, але на вихід вони поки не їдуть.
    _об3 = {k: float(v) for k, v in (d.get("обхвати") or {}).items()
            if v not in (None, "")}
    _тіло3 = (ПС.тіло(float(d["зріст"]), _об3)
              if d.get("зріст") not in (None, "") and len(_об3) >= 3 else None)
    _к3["опції"] = _АК.команди_розкладки(_для_к3, гардероб=d.get("гардероб"))
    _вш = _ВШ.перевірити(_для_к3, тіло=_тіло3,
                         темп_c=(d.get("сценарій") or {}).get("темп_c"),
                         вітер=(d.get("сценарій") or {}).get("вітер"),
                         тривалість_год=(d.get("сценарій") or {}).get("тривалість_год"))
    _к3["команди"] = list(_вш.get("команди") or [])
    # ── ОПИС_V1, А НЕ ПРОЗА (Т-06, крок 2) ───────────────────────────────────
    # НОМЕР ФОТО РАХУЄТЬСЯ РАЗ, І ТАМ, ДЕ ФОТО РОЗДАЮТЬСЯ. Доти промпт рахував
    # його словами («· фото 3–4 — сукня …»), а показ окремим списком `номерДоІд`,
    # і розбіжність двох лічб вішала «фото не те» на чужу річ. Тепер номери стоять
    # у самій речі (`фото_номери`), а модель у відповіді називає РІЧ, не знімок.
    _ном = d.get("номери") if isinstance(d.get("номери"), dict) else {}
    n = 0
    для_опису = []
    for р in речі:
        ф = list(р.get("фото") or [])
        р["фото_номери"] = list(range(n + 1, n + len(ф) + 1))
        n += len(ф)
        _ч = _частини.get(р["id"])
        для_опису.append(dict(
            н=(_ном.get(р["id"]) or р["id"]),
            слот=(_ч or р.get("слот")),
            назва=(("лише %s із комплекту: %s" % (_ч, р.get("назва"))) if _ч else р.get("назва")),
            магазин=str(р["id"]).split("@")[-1] if "@" in str(р["id"]) else None,
            фото=ф, фото_номери=р["фото_номери"],
            # її річ з фото (рядок 152): опис говорить про неї як про ЇЇ річ, не товар
            **({"її_річ": True} if р.get("власна") else {})))
    # ── ПАЛІТРА ЖІНКИ ДОЇЖДЖАЄ ДО ОПИСУ (K-PAL-11/14/15, 17.09.2026) ─────────
    # Рахується тут наново, а не береться з пакета, і це рішення: `опис` — окремий
    # виклик, пул на ньому вже не будується (див. шапку про номери речей), а
    # практикова палітра залежить ЛИШЕ від рис і самозвіту, які в `d` є. Другого
    # відбору каталогу це не коштує. Мовчазний провал тут законний з тієї самої
    # причини, що й у каналі 3: палітра опис ДОДАЄ, а не гейтує.
    # П.14: `None` тут означає «практикової палітри в описі нема», і `опис_v1`
    # читає це як стан. Ковтати поломку в те саме `None` означало б зробити
    # вимір «палітра доїхала до опису» непроводимим. Риси й самозвіт беруться з
    # того самого `d`, що й решта виклику, — це не невідомий вхід.
    import palettes as _ПЛ
    _F_оп = _features(d)[0]        # `_features` віддає кортеж; риси — перший елемент
    _пал_опису = _ПЛ.для_пакета(_ПЛ.палітра_практична(
        _F_оп, source=d.get("source") or "uncontrolled", самозвіт=_самозвіт(d))) or None
    # ЇЇ ДЕНЬ (рядок 195): той самий опис дня, що в пакеті складання й у вердикті, — з
    # того самого `d` (сценарій злитий із паспортом), і речення моделі про день обраного
    # образу з вибору (`вибір.день`, показ шле його полем `день`).
    import сценарій as _СЦ
    _сцен_оп = _СЦ.з_показу(d.get("сценарій"), d.get("паспорт"))[0]
    опис_об = _PL.опис_v1(для_опису, образ=d.get("образ"), задум=d.get("підпис"),
                          випадок=d.get("випадок"), свідомі=d.get("свідомі"),
                          фото_є=bool(фото), канал_3=_к3, палітра=_пал_опису,
                          день=(_СЦ.день_словами(_сцен_оп) or None), день_образу=d.get("день"))
    # Розходження зі схемою — полем назовні, як у `запити` і `від_моделі` (Т-02).
    _пом = _ПР.перевірити(_ПР.СХЕМИ["ОПИС_V1"], опис_об)
    промпт = _json.dumps(_без_ід_глибоко(опис_об), ensure_ascii=False)
    return _json.dumps(dict(промпт=промпт, опис=опис_об, фото=фото, речі=речі,
                            обрізано=обрізано, усього_фото=усі, канал_3=_к3,
                            **({"протокол_помилки": _пом} if _пом else {})),
                       ensure_ascii=False, default=str)


def сум(речі):
    """Скільки фото разом несуть речі образу (для стелі `ФОТО_НА_ОБРАЗ`)."""
    return sum(len(р.get("фото") or []) for р in речі)
