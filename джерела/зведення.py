         "**10.09.2026 · докстрінг перестав рахуватись за виконуваний рядок**",
         "(`gate_reach.з_коду`). Дев'ять правил через це змінили вердикт: шість",
         "із «без сліду» в «тільки коментар» і три з «інфраструктури» в «нема в",
         "коді» — їхній єдиний «виконуваний» рядок стояв усередині докстрінга,",
         "тобто прилад рахував ОПИС правила за його виконання. З «цілого» не",
         "вийшло жодне: сліду ця правка не торкається. Числа не «погіршали» —",
         "вони вперше кажуть те, що є. Самі ID тут НЕ перелічені навмисно:",
         "`з_коду` сканує і цей файл, і список кодів у шапці зробив би їх",
         "«у коді», тобто документ про вимір перебив би вимір.", "",
         "**11.09.2026 · слід перестав дорівнювати знахідці** (наряд Н-P17).",
         "Колонка «знахідка» — нова: правило або віддало рядок споживачеві, або",
