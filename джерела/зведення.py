def тема_за_ід():
    """{ID: [файли тем, де він названий]}. Правило живе в кількох темах законно."""
    out = collections.defaultdict(list)
    for імя, текст in sorted(КР.текст().items()):
        for ід in КР.бази_в_тексті(текст):
            out[ід].append(імя)
    return out


def клас_вердикту(в):
    """«дубль → K-PC-05» і «дубль → функція» — ОДИН клас у лічбі, різні рядки в
    таблиці. Без цього таблиця часток розпалася б на сорок рядків по одному
    правилу в кожному, тобто перестала б бути лічбою; а зливати їх у самому
    вердикті означало б викинути єдине, що робить посилання перевірним, — ім'я
    того, на кого посилаються."""
    return в.split(" → ")[0]


def вердикт(клас, якщо, у_коді, лише_коментар, є_слід, є_знахідка,
            дубль=None, вердикт_дубля=None, механізм=None, механізм_є=False):
    """Вердикт по одному правилу — ЧИСТА функція над вимірами.

    Шість перших аргументів — виміри самого правила; чотири останні описують
    ПОСИЛАННЯ на чинне місце (`rule_genus`: поля `дубль` і `механізм`), і їх теж
    міряє викликач: `вердикт_дубля` — вердикт чинного правила з першого проходу,
    `механізм_є` — `rule_genus.механізм_живий` (getattr, не греп).

    ЧОМУ ОКРЕМО (Н-P17). Ця таблиця рішень стояла всередині `зібрати`, поруч із
    двома реальними прогонами моста, і перевірити її можна було лише прогнавши
    їх — чотири хвилини на одне твердження. Тому її й не перевіряв ніхто: коли
    «ціле» почало означати «лишив слід», це не зловив жоден тест. Тепер правило
    вердикту — значення, і `прилади/розділи_гейтів.py` звіряє його без батареї.

    `клас` — що правило ВИННЕ виходу (`gate_reach.клас_сліду`):
        «знахідка» — рядок для людини чи моделі; «слід» — іменований запис у
        точці спрацювання (правило-процес); «інфра» — нічого з двох.
    """
    if якщо == "ні":
        return "не кодом"
    if якщо == "заблоковано":
        return "без входу"
    # ── ДУБЛЬ: МЕХАНІЗМ ЖИВИЙ ПІД ЧУЖИМ ІМЕНЕМ (19.09.2026, тріажі #142/#143) ──
    # ЩО ЦЕ МІНЯЄ В РІШЕННІ. «Нема в коді» — це черга «лікувати кодом зараз», і
    # 50 правил стояли в ній, маючи ЖИВИЙ механізм під іншим ID (`de00`,
    # `c_max_поверхня`, `reliability` під K-PC-05, `тиск_тону`, `СХЕМИ`…). Черга,
    # у якій «ще не зроблено» нерозрізнюване від «зроблено під іншим іменем», не
    # каже, що робити далі, — рівно та хвороба, від якої лікувався знаменник
    # `rule_genus`.
    # ПОРЯДОК НАВМИСНИЙ: власний виконуваний рядок сильніший за посилання. Правило,
    # яке стоїть у коді САМЕ, дістає свій вимір, а не мітку дубля; мітка діє лише
    # там, де власного рядка нема. Інакше запис у реєстрі вмів би сховати те, що
    # правило спрацьовує й мовчить («лише слід»).
    if not у_коді and (дубль or механізм):
        if дубль:
            # ДУБЛЬ ЗЛАМАНОГО МЕХАНІЗМУ НІЧИМ НЕ ПОКРИТИЙ. «Ціле» й
            # «інфраструктура» — єдині два стани, у яких чинне правило справді
            # робить роботу; при будь-якому іншому посилання лишає обох у черзі,
            # і правило чесно вертається в «нема в коді». Інакше один запис
            # знімав би з черги двох — і того, хто посилається, і того, на кого.
            return ("дубль → %s" % дубль
                    if вердикт_дубля in ("ціле", "інфраструктура")
                    else "нема в коді")
        # `механізм_є` міряє `rule_genus.механізм_живий` через `getattr`, а не
        # грепом: перейменована функція мусить валити запис прогоном.
        return "дубль → функція" if механізм_є else "нема в коді"
    if клас == "інфра":
        return "інфраструктура" if у_коді else "нема в коді"
    if not у_коді and not лише_коментар:
        return "нема в коді"
    if not у_коді:
        return "тільки коментар"
    if клас == "слід":
        # Правило-процес: іменований запис і Є його законним виходом.
        return "ціле" if є_слід else "без сліду"
    if є_знахідка:
        return "ціле"
    # Спрацювало, записалось у лог і не сказало споживачеві нічого. Доти, доки
    # це рахувалось «цілим», 31 правило стояло в чисельнику покриття мовчки.
    return "лише слід" if є_слід else "без сліду"


def зібрати():
    корп = sorted(КР.ід())
    теми = тема_за_ід()
    код = ГД.з_коду(os.path.dirname(os.path.abspath(__file__)) or ".")
    # ТРИ РУКИ БАТАРЕЇ ВІДДАЮТЬ DICT, А НЕ КОРТЕЖ (19.09.2026, знайдено прогоном).
    # Тут стояли розпаковки на 5, 3 і 2 елементи, а `gate_reach` уже віддавав
    # словники — і сам собі це пояснив: «кожен новий канал виходу означав переписати
    # три розпаковки». Свій же гейт він переписав, а цей викликач — ні, тож прилад
    # падав `ValueError: too many values to unpack` НА ПЕРШОМУ Ж рядку батареї, і
    # `ЗВЕДЕННЯ.md` не міг перегенеруватись узагалі (файл у теці — з рівня 7).
    # ДВА НОВІ КАНАЛИ ТУТ НЕ ЧИТАЮТЬСЯ НАВМИСНО. `спільні` (правило назвало себе на
    # ЧУЖІЙ знахідці) і `чекліст` (пункт зі станом «провал/пройдено/без входу») —
    # слабші твердження за власну знахідку, і `gate_reach` рахує їх окремими
    # числами саме тому. Влити їх сюди під виглядом лагодження падіння означало б
    # мовчки посунути вердикти десяткам правил; це окреме рішення й окремий наряд.
    _б = ГД.прогін()
    _зібр = ГД.прогін_зібраного()
    # ДРУГА ПОЛОВИНА ПЕТЛІ. Без неї «без сліду» діставали всі правила, що живуть
    # лише в суді над образом МОДЕЛІ (K-COMP-01, K-PAL-18, структура, канал_3):
    # батарея моста їх просто не викликала. Див. `gate_reach.прогін_від_моделі`.
    _мод = ГД.прогін_від_моделі()
    збої = _б["збої"]
    слід = _б["слід"] | _зібр["слід"] | _мод["слід"]
    знахідки = _б["знахідки"] | _зібр["знахідки"] | _мод["знахідки"]
    рядки = []
    for ід in корп:
        р = РР.рід(ід)
        ф = код.get(ід) or {}
        у_коді = sorted(f for f, як in ф.items() if як == "код")
        лише_ком = sorted(f for f, як in ф.items() if як == "коментар")
        є_слід = ід in слід
        є_знахідка = ід in знахідки
        # КЛАС СЛІДУ — ОДИН НА ПРОЄКТ І ЛЕЖИТЬ У `gate_reach` (Н-P17). Тут стояло
        # `РР.слід(ід) == "інфра"`, тобто два класи з трьох; третій — «правило-
        # процес, слід законний» — записаний поіменно в `gate_reach.СЛІД_ЗАКОННИЙ`
        # разом із причиною по кожному з 31 ID проби P17.
        клас = ГД.клас_сліду(ід)
        якщо = р.get("виконуваний")
        # ПЕРШИЙ ПРОХІД — БЕЗ ДУБЛІВ. Вердикт правила, на яке посилаються, мусить
        # бути виміряний ДО того, як посилання щось із нього зробить: інакше
        # порядок абетки вирішував би, чи покритий дубль, а два правила, що
        # послались одне на одне, покрили б себе самі.
        в = вердикт(клас, якщо, у_коді, лише_ком, є_слід, є_знахідка)
        # РОЗБІЖНІСТЬ НАМІРУ Й МІСЦЯ (наряд Н-V21-045). Предикат один на три
        # звіти й лежить у `gate_reach`, бо його читають і `правила`, і гейт.
        розб = ГД.розбіжність_шару(р.get("шар"), у_коді)
        рядки.append(dict(
            правило=ід,
            тема=";".join(os.path.basename(x).split("_")[0] for x in теми.get(ід, [])) or "—",
            рід=р.get("рід", "?"), мусить=якщо,
            місце=(р.get("шар") or "—"),
            у_коді=",".join(x[:-3] for x in у_коді) or "—",
            лише_коментар=",".join(x[:-3] for x in лише_ком) or "",
            слід=("так" if є_слід else "ні"),
            знахідка=("так" if є_знахідка else "ні"),
            клас_сліду=клас,
            вердикт=в,
            розбіжність=розб,
            блокер=(р.get("блокер") or ""),
            дубль=(р.get("дубль") or ""),
            механізм=(р.get("механізм") or ""),
            клас=клас, якщо=якщо, _у_коді=у_коді, _лише_ком=лише_ком,
            _слід=є_слід, _знахідка=є_знахідка,
            чому=(р.get("чому") or "")))
    # ДРУГИЙ ПРОХІД: посилання на чинне правило. Глибина рівно одна — дубль дубля
    # не розвʼязується, бо правило, яке саме лише посилається, роботи не робить і
    # підставою для другого посилання бути не може.
    базовий = {r["правило"]: r["вердикт"] for r in рядки}
    for r in рядки:
        if not (r["дубль"] or r["механізм"]):
            continue
        r["вердикт"] = вердикт(
            r["клас"], r["якщо"], r["_у_коді"], r["_лише_ком"],
            r["_слід"], r["_знахідка"],
            дубль=(r["дубль"] or None), вердикт_дубля=базовий.get(r["дубль"]),
            механізм=(r["механізм"] or None),
            механізм_є=РР.механізм_живий(r["механізм"]))
    for r in рядки:
        for к in ("клас", "якщо", "_у_коді", "_лише_ком", "_слід", "_знахідка"):
            del r[к]
    return рядки, збої


def друк(рядки, збої):
    # ЛІЧБА — ЗА КЛАСОМ, ПЕРЕЛІК — ПОІМЕННО. «дубль → K-PC-05» і «дубль → функція»
    # в одному рядку лічби; на кого саме посилається кожне правило, видно в його
    # рядку таблиці й у переліку нижче.
    c = collections.Counter(клас_вердикту(r["вердикт"]) for r in рядки)
    print("ЗВЕДЕННЯ: %d правил корпусу" % len(рядки))
    if збої:
        print("  ⛔ %d викликів моста впало — числа нижче НЕПОВНІ" % len(збої))
    for в, n in c.most_common():
        print("  %-16s %4d  (%.0f %%)" % (в, n, 100.0 * n / max(1, len(рядки))))
    print()
    _розб = [r for r in рядки if r.get("розбіжність")]
    print("  шар≠код: %d  (оголошений шар не збігається з кодом)" % len(_розб))
    print()
    if _розб:
        print("── ШАР≠КОД (%d) ──" % len(_розб))
        print("   (оголошений шар — намір; «у коді» — вимір. Розбіжність не каже,")
        print("    хто з двох правий: або правило живе не там, або довідник бреше)")
        for r in _розб:
            print("   %-12s оголошено %-30s у коді %s"
                  % (r["правило"], r["місце"][:30], r["у_коді"][:34]))
        print()
    for в in ("лише слід", "без сліду", "тільки коментар", "нема в коді", "дубль"):
        сп = [r for r in рядки if клас_вердикту(r["вердикт"]) == в]
        if not сп:
            continue
        print("── %s (%d) ──" % (в.upper(), len(сп)))
