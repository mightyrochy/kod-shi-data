# -*- coding: utf-8 -*-
"""ЗВЕДЕННЯ АУДИТУ: по рядку на кожне правило корпусу.

ЧОМУ ЦЕ ПРИЛАД, А НЕ ДОКУМЕНТ. Таблиця на 382 рядки, написана руками, застаріє
на першій же правці й не буде перевірною: рівно те, від чого проєкт лікується
всім іншим у цій теці. Тут кожна колонка — вимір, і кожен прогін дає поточний
стан, а не знімок чиєїсь пам'яті.

КОЛОНКИ І ЗВІДКИ ВОНИ:
  правило      — ID із корпусу (`корпус.ід`)
  тема         — файл теми, у якому він названий (перший за абеткою, якщо кілька)
  рід          — `rule_genus.рід`: образ / дані / процес, і чи МАЄ бути кодом
  місце        — оголошений шар із того ж реєстру
  у коді       — файли, де ID стоїть у ВИКОНУВАНОМУ рядку (`gate_reach.з_коду`)
  слід         — чи правило назвало себе у виході реального прогону моста
                 (`gate_reach.прогін` + `прогін_зібраного` + `прогін_від_моделі`:
                 три ноги петлі — запит, суд над зібраним, суд над образом моделі)
  вердикт      — виводиться з попередніх колонок, за таблицею нижче

ВЕРДИКТИ, І ЧОМУ САМЕ ТАКІ:
  ціле          — має бути кодом, є у виконуваному коді, лишає слід на вході
  без сліду     — є в коді, але себе не називає: лог не може приписати йому різницю
  тільки коментар — ID згадано, виконуваного рядка нема
  нема в коді   — має бути кодом і не реалізоване
  без входу     — реєстр каже «заблоковано», і блокер названий: це ЧЕРГА, не провал
  інфраструктура — працює всередині обчислення, іменованого сліду не винне
  не кодом      — у цьому шарі кодом бути не має

ЧОГО ЦЕЙ ФАЙЛ НЕ КАЖЕ (та сама межа, що в решті приладів): чи правило ПРАВЕ.
Він каже, чи воно ДІЄ. Поріг може бути хибним у правила з вердиктом «ціле».

Прогін:  python3 зведення.py [--md ФАЙЛ]     (~4 хв: два реальні прогони моста)
"""
import sys, os, collections

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)) or ".")
import корпус as КР
import rule_genus as РР
import gate_reach as ГД


def тема_за_ід():
    """{ID: [файли тем, де він названий]}. Правило живе в кількох темах законно."""
    out = collections.defaultdict(list)
    for імя, текст in sorted(КР.текст().items()):
        for ід in set(КР.ID_ПРАВИЛА.findall(текст)):
            out[ід].append(імя)
    return out


def зібрати():
    корп = sorted(КР.ід())
    теми = тема_за_ід()
    код = ГД.з_коду(os.path.dirname(os.path.abspath(__file__)) or ".")
    _вих, _n, слід, збої = ГД.прогін()
    слід_зібр, _гілки = ГД.прогін_зібраного()
    # ДРУГА ПОЛОВИНА ПЕТЛІ. Без неї «без сліду» діставали всі правила, що живуть
    # лише в суді над образом МОДЕЛІ (K-COMP-01, K-PAL-18, структура, канал_3):
    # батарея моста їх просто не викликала. Див. `gate_reach.прогін_від_моделі`.
    слід_мод = ГД.прогін_від_моделі()
    слід = слід | слід_зібр | слід_мод
    рядки = []
    for ід in корп:
        р = РР.рід(ід)
        ф = код.get(ід) or {}
        у_коді = sorted(f for f, як in ф.items() if як == "код")
        лише_ком = sorted(f for f, як in ф.items() if як == "коментар")
        є_слід = ід in слід
        якщо = р.get("виконуваний")
        if якщо == "ні":
            в = "не кодом"
        elif якщо == "заблоковано":
            в = "без входу"
        elif РР.слід(ід) == "інфра":
            в = "інфраструктура" if у_коді else "нема в коді"
        elif not у_коді and not лише_ком:
            в = "нема в коді"
        elif not у_коді:
            в = "тільки коментар"
        elif є_слід:
            в = "ціле"
        else:
            в = "без сліду"
        рядки.append(dict(
            правило=ід,
            тема=";".join(os.path.basename(x).split("_")[0] for x in теми.get(ід, [])) or "—",
            рід=р.get("рід", "?"), мусить=якщо,
            місце=(р.get("шар") or "—"),
            у_коді=",".join(x[:-3] for x in у_коді) or "—",
            лише_коментар=",".join(x[:-3] for x in лише_ком) or "",
            слід=("так" if є_слід else "ні"),
            вердикт=в,
            блокер=(р.get("блокер") or ""),
            чому=(р.get("чому") or "")))
    return рядки, збої


def друк(рядки, збої):
    c = collections.Counter(r["вердикт"] for r in рядки)
    print("ЗВЕДЕННЯ: %d правил корпусу" % len(рядки))
    if збої:
        print("  ⛔ %d викликів моста впало — числа нижче НЕПОВНІ" % len(збої))
    for в, n in c.most_common():
        print("  %-16s %4d  (%.0f %%)" % (в, n, 100.0 * n / max(1, len(рядки))))
    print()
    for в in ("без сліду", "тільки коментар", "нема в коді"):
        сп = [r for r in рядки if r["вердикт"] == в]
        if not сп:
            continue
        print("── %s (%d) ──" % (в.upper(), len(сп)))
        for r in сп:
            print("   %-12s %-10s %-28s %s" % (r["правило"], r["тема"][:10],
                                               r["місце"][:28], r["у_коді"][:34]))
        print()


def markdown(рядки, збої):
    c = collections.Counter(r["вердикт"] for r in рядки)
    л = ["# ЗВЕДЕННЯ АУДИТУ: правило → місце → поведінка → вердикт", "",
         "Породжено `джерела/зведення.py`. Кожна колонка — вимір, не пам'ять.", ""]
    if збої:
        л.append("⛔ **%d викликів моста впало — числа неповні.**" % len(збої))
        л.append("")
    л += ["| вердикт | правил | частка |", "|---|---:|---:|"]
    for в, n in c.most_common():
        л.append("| %s | %d | %.0f %% |" % (в, n, 100.0 * n / max(1, len(рядки))))
    л += ["", "## Повна таблиця", "",
          "| правило | тема | рід | мусить бути кодом | оголошене місце | у коді | слід | вердикт |",
          "|---|---|---|---|---|---|---|---|"]
    for r in рядки:
        л.append("| `%s` | %s | %s | %s | %s | %s | %s | **%s** |"
                 % (r["правило"], r["тема"], r["рід"], r["мусить"],
                    r["місце"], r["у_коді"], r["слід"], r["вердикт"]))
    return "\n".join(л) + "\n"


if __name__ == "__main__":
    рядки, збої = зібрати()
    друк(рядки, збої)
    if "--md" in sys.argv:
        шлях = sys.argv[sys.argv.index("--md") + 1]
        open(шлях, "w", encoding="utf-8").write(markdown(рядки, збої))
        print("записано:", шлях)
