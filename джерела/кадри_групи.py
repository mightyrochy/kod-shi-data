# -*- coding: utf-8 -*-
"""ПРИЙМАЧ ВИМІРІВ ГАЛЕРЕЙ (рядок 5697, §3.5 проєкту 5617): результат ноутбука → `каталог_кадри`
і кадри речі, згруповані за кольором навколо якоря варіанта.

ЩО ПРИХОДИТЬ. Той самий формат, що в `каталог_кадри.json.gz`: {"мета", "записи": {id: [кадр]}}, кадр
= {файл, url, lab, слово, частка, hex, кластери, маска, частка_маски, чому, клас}. Пише його
`жнива_кадри.py --галереї` на ноутбуці; сюди він приходить файлом, моделей і мережі тут нема.

ЩО РОБИТЬ. `прийняти` перевіряє записи (биті відкидає з друком, не мовчки), зливає їх у наявний файл
за файлом кадру (нові замінюють старі, решта лишається) і атомарно пише. `групи_кадрів` ділить
кадри однієї речі: службові (етикетка, упаковка, чужа річ, підошва — не свідки кольору), без виміру,
а виміряні — за сім'єю тону; група якоря (кадр жнив варіанта) — ті кадри, чий колір узгоджується
з кольором якоря тим самим судом, що й спір кольору (`фід_кадр_колір.узгоджений`). Слів назви
код не читає (п.12): лише ключі лексикону з виміру.

ЗАПУСК (хмара, тека `джерела`): python3 кадри_групи.py --вхід результат.json.gz [--сухо]"""
import argparse, collections, gzip, json, os, sys
import verify as V
from фід_збагачення import колір_збагачення
from фід_кадр_колір import НЕ_СВІДКИ, КАДР_КАРТКИ, КАДРИ_ІМ, узгоджений
from фід_фото import _файл_фото

ТУТ = os.path.dirname(os.path.abspath(__file__)) or "."
ВИХІД = os.path.join(ТУТ, КАДРИ_ІМ + ".gz")
КЛАСИ = frozenset(("ціла_річ", "на_моделі", "деталь", "підошва", "етикетка", "упаковка", "інша_річ", "порожня"))


def кадр_справний(в):
    """Причина, чому запис кадру не можна приймати, або None."""
    if not (isinstance(в, dict) and в.get("файл") and в.get("url")):
        return "нема файла чи адреси"
    if в.get("клас") and в["клас"] not in КЛАСИ:
        return "клас %r поза переліком" % в["клас"]
    if в.get("lab"):
        lab = в["lab"]
        if not (isinstance(lab, (list, tuple)) and len(lab) == 3 and all(isinstance(x, (int, float)) for x in lab)):
            return "lab не з трьох чисел"
        if в.get("слово") not in V.ЛЕКСИКОН:
            return "слово %r поза лексиконом" % в.get("слово")
    return None


def злити_записи(старі, нові):
    """Записи кадрів речі: нові замінюють старі за файлом, решта старих лишається (порядок
    старих, нові в кінець): прогін галереї дописує, а не переписує вже виміряне."""
    за_файлом = {в.get("файл"): в for в in старі or ()}
    for в in нові:
        за_файлом[в.get("файл")] = в
    return list(за_файлом.values())


def групи_кадрів(зб, записи):
    """Кадри речі за кольором навколо якоря. `зб` — придатне збагачення (кадр жнив = якір) чи None.

    → {якір: файл|None, слово_якоря, групи: [{сім_я, якір: bool, слова, кадри: [{файл, url, клас, слово}]}],
       службові: [файл], без_виміру: [файл], для_картки: [url]}. Групи — якір першою, далі за розміром.
    `для_картки` — кадри групи якоря, де річ ціла (клас ціла_річ чи на_моделі; кадр без класу на
    картку не йде, як у `після_спору`), у порядку галереї; кадр жнив першим."""
    якір_файл = якір_слово = якір_сім = None
    якір_lab = None
    if зб:
        якір_файл = _файл_фото(зб.get("фото"))
        якір_слово, якір_lab, _ = колір_збагачення(зб)
        якір_сім = V.сім_я_слова(якір_слово)
    службові, без_виміру, групи = [], [], collections.OrderedDict()
    for в in записи or ():
        if в.get("клас") in НЕ_СВІДКИ:
            службові.append(в["файл"])
        elif not (в.get("lab") and в.get("слово") in V.ЛЕКСИКОН):
            без_виміру.append(в["файл"])
        else:
            сім = V.сім_я_слова(в["слово"])
            ключ = якір_сім if якір_слово and узгоджений(якір_слово, tuple(в["lab"]), сім) else сім
            групи.setdefault(ключ, []).append(в)
    вих = []
    for сім, кадри in групи.items():
        вих.append(dict(сім_я=сім, якір=bool(якір_слово) and сім == якір_сім,
                        слова=[с for с, _ in collections.Counter(в["слово"] for в in кадри).most_common()],
                        кадри=[dict(файл=в["файл"], url=в["url"], клас=в.get("клас"), слово=в["слово"]) for в in кадри]))
    вих.sort(key=lambda г: (not г["якір"], -len(г["кадри"])))
    для_картки = []
    if якір_слово:
        для_картки = [к["url"] for г in вих if г["якір"] for к in г["кадри"] if к["клас"] in КАДР_КАРТКИ]
    return dict(якір=якір_файл, слово_якоря=якір_слово, групи=вих, службові=службові,
                без_виміру=без_виміру, для_картки=для_картки)


def записати(шлях, дані):
    """gzip JSON атомарно: тимчасовий файл поруч і `os.replace` — обрив не лишає битого файла."""
    тимч = шлях + ".tmp"
    with gzip.open(тимч, "wt", encoding="utf-8") as f:
        json.dump(дані, f, ensure_ascii=False)
    os.replace(тимч, шлях)


def прийняти(вхід, вихід=ВИХІД, сухо=False):
    """Результат ноутбука `вхід` → злито у `вихід`. Повертає (прийнято, відкинуто, речей, нових_речей)."""
    def читати(ш):
        with gzip.open(ш, "rt", encoding="utf-8") as f:
            return json.load(f)
    нові = читати(вхід)
    if (нові.get("мета") or {}).get("сухо"):
        raise SystemExit("вхід — сухий прогін (маски не кликали): приймати нічого, виміру в ньому нема")
    дані = читати(вихід) if os.path.exists(вихід) else {"мета": {}, "записи": {}}
    прийнято = відкинуто = нових_речей = 0
    for ід, кадри in (нові.get("записи") or {}).items():
        добрі = []
        for в in кадри:
            причина = кадр_справний(в)
            if причина:
                відкинуто += 1
                print("відкинуто %s: %s" % (ід, причина))
            else:
                добрі.append(в)
        прийнято += len(добрі)
        нових_речей += ід not in дані["записи"]
        if добрі:
            дані["записи"][ід] = злити_записи(дані["записи"].get(ід), добрі)
    дані["мета"] = dict(дані.get("мета") or {}, **{к: в for к, в in (нові.get("мета") or {}).items() if к not in ("записів", "кадрів")},
                        записів=len(дані["записи"]), кадрів=sum(len(в) for в in дані["записи"].values()))
    if not сухо:
        записати(вихід, дані)
    return прийнято, відкинуто, len(нові.get("записи") or {}), нових_речей


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--вхід", required=True)
    ap.add_argument("--вихід", default=ВИХІД)
    ap.add_argument("--сухо", action="store_true", help="перевірити й злити в пам'яті, файл не писати")
    а = ap.parse_args()
    п, в, р, н = прийняти(а.вхід, а.вихід, а.сухо)
    print("прийнято кадрів %d, відкинуто %d; речей у вході %d, з них нових %d%s" % (п, в, р, н, " (сухо)" if а.сухо else ""))
    return 1 if в else 0


if __name__ == "__main__":
    sys.exit(main())
