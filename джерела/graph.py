import collections

# ── ВУЗЛИ ───────────────────────────────────────────────────────────────────
СЛОТИ = ("верх", "низ", "сукня", "комплект", "верхній_шар", "взуття", "сумка", "шарф",
         "головний_убір", "пояс", "колготи", "шкарпетки", "сережки", "кольє",
         "намисто", "брошка", "браслет", "каблучка", "окуляри")
ЗОНИ_ТІЛА = ("обличчя", "шия", "плечі", "груди", "талія", "високе_стегно", "стегна",
             "стегно", "коліно", "литка", "щиколотка", "стопа", "руки", "спина", "декольте")
ЛЮДИНА = "людина"


# ── ЗОНА РЕЧІ В ПРОСТОРІ ЗНАЧЕНЬ ─────────────────────────────────────────────
def зона(р):
    """Осі речі як інтервали з джерелом. Нічого не вгадується: невідома вісь
    відсутня, а не заповнена дефолтом.

    колір: L/C/h — інтервали; `розкид` — скаляр точності (ΔE-подібний) для
           парних правил: слово → півширина L-вікна; фото → виміряний розкид
           пікселів; фото без розкиду → None (точка, позначена джерелом).
    край:  (низ_см − розкид, низ_см + розкид) — лише коли край не з дефолту.
    формальність: (мін, макс) типу — вже інтервал у ТИП_ФОРМАЛЬНІСТЬ.
    сезон: смуга °C тканини."""
    з = {}
    в = р.get("вікно")
    lab = р.get("lab")
    дж = р.get("джерело_кольору")
    if дж == "назва_вікно" and в:
        з["колір"] = dict(L=(float(в[0]), float(в[1])), C=(float(в[2]), float(в[3])), h=в[4],
                          розкид=round((float(в[1]) - float(в[0])) / 2.0, 1),
                          джерело="слово «%s»%s" % (р.get("колір_ім"),
                                                     " (%s)" % р["колір_модифікатор"] if р.get("колір_модифікатор") else ""),
                          впевненість=р.get("впевненість"))
    elif lab is not None:
        рз = р.get("розкид")
        L = float(lab[0])
        з["колір"] = dict(L=(max(0.0, L - (рз or 0.0)), min(100.0, L + (рз or 0.0))),
                          C=None, h=None, розкид=рз,
                          джерело=("фото, розкид %.1f ΔE" % рз) if рз is not None else "фото без виміряного розкиду — точка",
                          впевненість=р.get("впевненість"))
    if р.get("край_джерело") not in (None, "дефолт слота") and р.get("низ_см") is not None:
        рз = float(р.get("край_розкид_см") or 0.0)
        з["край"] = dict(см=(float(р["низ_см"]) - рз, float(р["низ_см"]) + рз),
                         джерело=р.get("край_джерело"), рівень=р.get("довжина_рівень"))
    if р.get("тип"):
        try:
            import outfit as _O
            ф = _O.ТИП_ФОРМАЛЬНІСТЬ.get(р["тип"])
            if ф: з["формальність"] = dict(інтервал=tuple(ф), джерело="тип «%s»" % р["тип"])
        except Exception:
            pass
    if р.get("сезон_тканини"):
        з["сезон"] = dict(смуга=tuple(р["сезон_тканини"]), джерело=р.get("сезон_за_чим"))
    if р.get("крій"):
        з["крій"] = dict(значення=р["крій"], джерело=р.get("крій_за_чим"))
    return з


def розкид_зі_слова(р):
    """Точність кольору речі, взятого зі слова, у тих самих одиницях, що розкид
    пікселів фото (ΔE-подібно; для нейтралей ΔE00 ≈ ΔL). None, якщо колір не зі
    слова або вікна нема."""
    в = р.get("вікно")
    if р.get("джерело_кольору") == "назва_вікно" and в:
        return round((float(в[1]) - float(в[0])) / 2.0, 1)
    return None


# ── ГІПЕРГРАФ ЗНАХІДОК ───────────────────────────────────────────────────────
ОБРАЗ = "образ"

def _вузли_знахідки(з, назва_у_слот, усі_слоти=()):
    """Вузли, на які інцидентне ребро: слоти названих речей + зони тіла з тексту.

    Ребро, що називає ВСІ речі образу (K-BOD-02 «боксі-крій ховає талію», K-CUT-00,
    K-COMP-01), не локалізує нічого: гіперребро над усією множиною вершин несе
    напругу образу, не слота. Воно йде у вузол «образ», інакше взуття ставало б
    «вузьким» через правило про силует, у якому взуття не бере участі (виміряно
    на першому ж прогоні: взуття 0.71 з шести ребер, п'ять із них — над усім)."""
    вузли = set()
    слоти = set()
    for ім in (з.get("речі") or []):
        # правило може назвати СЛОТ замість речі (K-COL-JOIN: «взуття») — 114 із
        # 3965 ребер на прогоні 28.08 падали через це у вузол «людина»
        с = назва_у_слот.get(ім) or (ім if ім in СЛОТИ else None)
        if с: слоти.add(с)
    # Ребро над усім образом → «образ». «Усе» рахується з поправкою на ОДИН прихований
    # слот: шар видимості (outfit.елементи) викидає річ під застібнутим верхнім шаром, і
    # правило над образом (K-INT-04 «0 джерел інтересу») називає 4 речі з 5 — доти воно
    # падало на чотири слоти й робило «сумку»/«верх» вузькими через твердження про ОБРАЗ
    # (холодна-темна · прогулянка 6°, 200/200 комбінацій, 28.08.2026).
    # Дужки поставлені явно. Було: `A and B and C and D or (E and F and G)` з
    # переносом рядка — вираз, що читається однією групою, а обчислюється двома
    # (`and` звʼязує тугіше за `or`). Тут групування збігалося з наміром, і це
    # перевірено вичерпно на всіх підмножинах пʼятьох слотів: 0 розбіжностей.
    # Дужки лишаються, бо наступна правка такого виразу вже не буде безпечною.
    _над_усім = (len(слоти & set(усі_слоти)) >= max(2, len(усі_слоти) - 1)
                 and len(слоти) >= 3) or слоти >= set(усі_слоти)
    if усі_слоти and len(усі_слоти) > 1 and _над_усім:
        вузли.add(ОБРАЗ)
    else:
        вузли |= слоти
    текст = " ".join(str(з.get(k) or "") for k in ("суть", "чому")).lower()
    for зт in ЗОНИ_ТІЛА:
        if ("«%s»" % зт) in текст or (" %s " % зт) in (" " + текст + " "):
            вузли.add(зт)
    if not вузли:
        # правило над людиною чи над усім образом (K-CLR, K-PAL, K-INT-04)
        вузли.add(ЛЮДИНА)
    return вузли


def граф(знахідки, речі):
    """Гіперграф оціненої комбінації.

    ребра: [{ід, правило, вузли, напруга, регістр, блокує, суть}]
    вузли: {вузол: {ребер, напруга, ребра}} — відсортовано за напругою.
    Питання (сила «питання», напруга 0) лишаються ребрами з напругою 0: вони
    показують, ДЕ бракує входу, і це теж інцидентність."""
    назва_у_слот = {}
    for r in речі:
        for k in ("назва", "id", "річ"):
            if r.get(k): назва_у_слот[str(r[k])] = r.get("слот")
    усі_слоти = tuple(sorted({r.get("слот") for r in речі if r.get("слот")}))
    ребра = []
    for i, з in enumerate(знахідки):
        if not з.get("правило"): continue
        нп = з.get("сила_нп")
        # ПИТАННЯ НЕ ТИСНЕ. Докстрока обіцяла це від 28.08, а код брав сила_нп
        # питання (0.25, «категорія — виміру немає») як напругу. Виміряно після
        # того, як K-BOD-02 над дефолтним кроєм став питанням: вузол переможця
        # «верх» 0.438 із ЧОТИРЬОХ питань (K-FIT-03, K-BOD-02×2, K-CUT-00) — тобто
        # місце, де бракує входу, видавалось за місце, де образу вузько, і O4
        # «послабити вузол» шукав верх без питань, якого в пулі нема (крій у 12 %).
        питання = (з.get("регістр") == "питання" or з.get("сила") == "питання")
        ребра.append(dict(ід="%s#%d" % (з["правило"], i), правило=з["правило"],
                          вузли=sorted(_вузли_знахідки(з, назва_у_слот, усі_слоти)),
                          напруга=(1.0 if з.get("блокує") else 0.0 if питання or нп is None else float(нп)),
                          регістр=з.get("регістр"), блокує=bool(з.get("блокує")), питання=питання,
                          суть=str(з.get("суть") or "")[:120]))
    вузли = {}
    for р in ребра:
        for u in р["вузли"]:
            в = вузли.setdefault(u, dict(вузол=u, ребер=0, напруга=0.0, ребра=[]))
            в["ребер"] += 1
            # гіперребро над n вузлами ділить напругу між ними (ребро над усім
            # образом уже зібране у вузол «образ» і слотів не навантажує)
            в["напруга"] += р["напруга"] / max(1, len(р["вузли"]))
            в["ребра"].append(р["правило"])
    for в in вузли.values():
        в["напруга"] = round(в["напруга"], 3)
    впоряд = sorted(вузли.values(), key=lambda в: (-в["напруга"], -в["ребер"], в["вузол"]))
    return dict(ребра=ребра, вузли=впоряд)


def з_тілом(г, T, intent="conventional"):
    """Один граф на образ І тіло. Ребра тілесного гіперграфа (hypergraph.ребра —
    смуги прилягання, якір об'єму, одна лінія, мінімум носіння) додаються до ребер
    образу з тими самими полями. Вони не залежать від речей, тож у пулі це
    резонанс (не ключ), але в інцидентності вони — ті самі вузли зон тіла, що й
    у ребер образу: «талія» тепер несе і K-FIT-03 речі, і смугу прилягання тіла
    в одному числі. До 28.08.2026 це були два об'єкти в двох модулях."""
    if T is None: return г
    try:
        import hypergraph as ГГ
        пр = ГГ.простір(T, intent=intent, сітка="крої")
        тіл = ГГ.ребра(T, пр, intent=intent)
    except Exception:
        return г
    ребра = list(г["ребра"])
    for р in тіл:
        # ребра тіла лягають лише на ЗОНИ ТІЛА: вони не залежать від речей і не
        # мають права зсувати вузол напруги слотів (виміряно: інакше «взуття» → «верх»)
        вузли = sorted(set(u for u in (р.get("вузли") or []) if u in ЗОНИ_ТІЛА) or [ЛЮДИНА])
        ребра.append(dict(ід="тіло:%s" % р.get("ід"), правило=р.get("джерело") or ("тіло:%s" % р.get("ід")),
                          вузли=вузли, напруга=float(р.get("напруга") or 0.0), регістр="тіло",
                          блокує=False, суть=str(р.get("рядок") or р.get("ід") or "")[:120], тіло=True))
    вузли = {}
    for р in ребра:
        for u in р["вузли"]:
            в = вузли.setdefault(u, dict(вузол=u, ребер=0, напруга=0.0, ребра=[]))
            в["ребер"] += 1; в["напруга"] += р["напруга"] / max(1, len(р["вузли"])); в["ребра"].append(р["правило"])
    for в in вузли.values(): в["напруга"] = round(в["напруга"], 3)
    return dict(ребра=ребра, вузли=sorted(вузли.values(), key=lambda в: (-в["напруга"], -в["ребер"], в["вузол"])),
                ребер_тіла=len(тіл))


def вузол_напруги(г, лише_слоти=True):
    """Найзавантаженіший вузол (слот або зона тіла). None, якщо напруги нема.
    `лише_слоти` — для портфеля: послабити можна лише те, що обирається."""
    for в in г["вузли"]:
        if в["напруга"] <= 0: return None
        if лише_слоти and в["вузол"] not in СЛОТИ: continue
        return в
    return None


# ── РОЗРІЗНЮВАЛЬНІСТЬ У ПУЛІ ─────────────────────────────────────────────────
def розрізнювальні(оцінені, поле="знахідки"):
    """Правила, чия напруга РІЗНИТЬСЯ між комбінаціями пулу. Повертає
    (розрізнювальні, резонансні) — множини правил і статистику по кожному.

    Правило, присутнє в усіх комбінаціях з тією самою напругою, або відсутнє
    майже скрізь з тією самою напругою, не впорядковує пул: воно резонанс
    (пояснення), не критерій. Правило, присутнє в частині комбінацій, розрізняє
    (наявність/відсутність — теж різниця)."""
    n = len(оцінені)
    за_правилом = collections.defaultdict(list)
    for x in оцінені:
        суми = collections.defaultdict(float)
        for з in x.get(поле) or []:
            if з.get("правило") and not з.get("блокує") and з.get("сила_нп") is not None:
                суми[з["правило"]] += float(з["сила_нп"])
        for р, s in суми.items():
            за_правилом[р].append(round(s, 4))
    розр, резон, стат = set(), set(), {}
    for р, значення in за_правилом.items():
        присутнє = len(значення)
        різних = len(set(значення))
        # константа в усіх комбінаціях → резонанс; є не скрізь або варіює → розрізняє
        if присутнє == n and різних == 1:
            резон.add(р)
        else:
            розр.add(р)
        стат[р] = dict(присутнє=присутнє, комбінацій=n, різних=різних,
                       мін=min(значення), макс=max(значення))
    return розр, резон, стат


def ключ_комбінації(x, розр):
    """Сума напруг розрізнювальних ребер (без блокерів) — ключ сортування.
    Резонансні ребра не входять: константа зі знаком — це шум."""
    return round(sum(float(з.get("сила_нп") or 0.0) for з in (x.get("знахідки") or [])
                     if з.get("правило") in розр and not з.get("блокує") and з.get("сила_нп") is not None), 4)


# ── СЛОВАМИ ─────────────────────────────────────────────────────────────────
def рядок_вузла(в, г):
    """Речення для «чому цей» / пакета моделі: де вузько, через які ребра і що
    саме в образі має мінятись, щоб вузол розв'язався."""
    if not в: return None
    ребра = [р for р in г["ребра"] if в["вузол"] in р["вузли"] and р["напруга"] > 0]
    ребра.sort(key=lambda р: -р["напруга"])
    важчі = ребра[:3]
    імена = ", ".join(sorted({р["правило"] for р in важчі}))
    # ── ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026) ────────────────────
    # Образ «три гучні хроми» (gate_reach.НАВМИСНІ), сцена «свято», той самий вузол:
    # before: вузол напруги — «низ» (0.36, 4 ребер: K-CLR-02, K-COMP-04);
    #         послабити його — значить міняти саме цей слот, а не суму
    # after:  вузол напруги — «низ» (0.36, 4 ребер: K-CLR-02, K-COMP-04);
    #         тримається зв'язкою «низ» + «верх» — міняти одну річ із неї
    # ЧОМУ СТАРИЙ ХВІСТ НЕДІЄВИЙ: він був ОДИН І ТОЙ САМИЙ у всіх 51 рядку прогону
    # батареї (17 навмисних образів × 3 сцени) — він пояснював НАШ спосіб рахувати
    # ключ («не суму»), а не те, з чим у образі щось робити. До ші через
    # `pipeline.промпт_ремонту` («вузьке місце: …») доїжджали ім'я слота, число й
    # три ID правил, яких їй не показують більше ніде; напрям дії — нікуди.
    # БІК НЕ ВИГАДУЄТЬСЯ І НЕ РАХУЄТЬСЯ ЗАНОВО: він читається з інцидентності тих
    # самих важчих ребер, що рядком вище дали `імена`. Ребро, яке не лежить на
    # жодному іншому СЛОТІ, тримається однією річчю — міняти треба її; ребро над
    # двома слотами тримається зв'язкою, і замінити можна будь-який її кінець.
    # Зони тіла у зв'язку не входять: їх не обирають, і назвати талію тим, «що
    # змінити», означало б послати ші міняти жінку, а не образ.
    сусіди = sorted({u for р in важчі for u in р["вузли"] if u != в["вузол"] and u in СЛОТИ})
    зв_язка = " + ".join("«%s»" % с for с in [в["вузол"]] + сусіди)
    # ── ЩО ЦЕ МІНЯЄ (правило 3, before/after, 08.09.2026, ревізія) ──────────
    # Синтетичний граф із двох ребер, що називають лише «талія» (K-FIT-03,
    # K-BOD-02), вузол напруги взято через `вузол_напруги(г, лише_слоти=False)`:
    # before: вузол напруги — «талія» (1.50, 2 ребер: K-BOD-02, K-FIT-03);
    #         це не слот — ребра лежать на образі цілому: міняти склад образу,
    #         а не одну річ
    # after:  вузол напруги — «талія» (1.50, 2 ребер: K-BOD-02, K-FIT-03);
    #         це не слот, а зона тіла — міняти те, що лягає на «талія»
    # ЧОМУ СТАРИЙ ХВІСТ НЕДІЄВИЙ: він казав про образ ЦІЛИЙ те, що виміряне на
    # ОДНІЙ зоні, — ребра лежали на талії, а речення посилало міняти склад усього
    # образу, тобто називало не те місце, де напруга. Гілка «образ»/«людина»
    # лишається дослівно як була; розведено ЛИШЕ формулювання, бо ЗОНИ_ТІЛА і
    # СЛОТИ — різні вузли з різним напрямом дії. Числа не додано жодного,
    # ЗОНИ_ТІЛА — та сама модульна константа, що вже вживана в `_вузли_знахідки`.
    if в["вузол"] not in СЛОТИ:
        if сусіди:
            куди = ("це не слот — міняти речі, що сходяться на ньому: %s"
                    % " + ".join("«%s»" % с for с in сусіди))
        elif в["вузол"] in ЗОНИ_ТІЛА:
            куди = "це не слот, а зона тіла — міняти те, що лягає на «%s»" % в["вузол"]
        else:
            куди = "ребра лежать на образі цілому — міняти склад образу, а не одну річ"
    elif сусіди:
        куди = "тримається зв'язкою %s — міняти одну річ із неї" % зв_язка
    else:
        куди = "інші слоти в цих ребрах не беруть участі — міняти саму річ у «%s»" % в["вузол"]
    return ("вузол напруги — «%s» (%.2f, %d %s: %s); %s"
            % (в["вузол"], в["напруга"], в["ребер"],
               "ребро" if в["ребер"] == 1 else "ребер", імена, куди))


def рядок_вузла_словами(в, г, скільки=2):
    """Те саме для МОДЕЛІ: без ID правил — лише суть ребер, що навантажують вузол.
    Модель не має бачити правил (принцип: код фільтрує, модель компонує)."""
    if not в: return None
    ребра = sorted([р for р in г["ребра"] if в["вузол"] in р["вузли"] and р["напруга"] > 0],
                   key=lambda р: -р["напруга"])[:скільки]
    суті = "; ".join(р["суть"].split(" — ")[0].split(":")[0] for р in ребра if р["суть"])
    # СИЛА ЙДЕ В МОВУ. Виміряно 28.08 після того, як питання перестали тиснути: у
    # «вечір 22°» вузол «взуття» мав 0.05 з одного hint «виріз взуття тут не вирішує
    # нічого» — і пакет казав моделі «тут сходиться найбільше умов, міняй це».
    # Слова напруги — ті самі, що в hypergraph.словами (одна шкала для тіла й образу).
    from hypergraph import словами as _сл
    return "«%s» — тут %s%s" % (в["вузол"], _сл(в["напруга"]) if в["напруга"] < 0.35 else "сходиться найбільше умов",
                                 (": " + суті) if суті else "")


def зона_словами(з):
    """Зона речі для пакета моделі — словами, без наших внутрішніх шкал."""
    ч = []
    к = з.get("колір")
    if к:
        L = к["L"]
        ч.append("світлота %d–%d (%s)" % (round(L[0]), round(L[1]), к["джерело"]))
    кр = з.get("край")
    if кр:
        ч.append("край %d–%d см від підлоги (%s)" % (round(кр["см"][0]), round(кр["см"][1]), кр["джерело"]))
    ф = з.get("формальність")
    if ф:
        ч.append("формальність %d–%d із 7" % ф["інтервал"])
    с = з.get("сезон")
    if с:
        hi = с["смуга"][1]
        ч.append("тканина на %s" % ("%d–%d °C" % (с["смуга"][0], hi) if hi < 900 else "від %d °C" % с["смуга"][0]))
    if з.get("крій"):
        ч.append("крій %s" % з["крій"]["значення"])
    return "; ".join(ч)
