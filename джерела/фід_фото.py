def заглушка_кадру(url):
    """Чи це намальована крамницею заглушка «фото нема»; `None` — коли ні."""
    баз = _файл_фото(url).split("/")[-1] if url else ""
    return "крамниця поставила замість фото свою заглушку" if ЗАГЛУШКА_ІМЕНІ.search(баз) else None


def _пропорція_фото(url):
    """Відношення ширини до висоти, коли розмір зашитий у шлях; інакше `None`.

    Читається з тих самих двох форм, що й `_площа_фото`, і тим самим апаратом:
    другий розбір адреси тут був би другим способом назвати те саме.
    """
    u = str(url or "").split("?")[0]
    for с in u.split("/"):
        м = _РОЗМІР_СЕГМЕНТ.match(с)
        if м:
            return int(м.group(1)) / int(м.group(2))
    м = _РОЗМІР_ХВІСТ.search(u)
    return int(м.group(1)) / int(м.group(2)) if м else None


