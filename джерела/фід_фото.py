# Доти порівняння `спільні.get(ф, 1) < СПІЛЬНЕ_ФОТО_ТОВАРІВ` стояло ТРЬОМА
# однаковими виразами в тілі `міст_опис._фото_речі` — і ЖОДНОГО разу в читанні
