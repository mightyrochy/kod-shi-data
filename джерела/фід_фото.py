СПІЛЬНЕ_ФОТО_ТОВАРІВ = 3


def _хост_фото(url):
    """Хост посилання в нижньому регістрі; порожньо, коли шлях відносний.

    Потрібен рівно для одного питання — «чи це адреса ТІЄЇ САМОЇ крамниці»:
    запасний шлях `_фото_речі` бере кадр жнив лише з хоста, з якого ця крамниця
    сама віддає фото у фіді.
    """
    u = str(url or "")
    if u.lower().startswith(("http://", "https://")):
        ч = u.split("/")
        return ч[2].lower() if len(ч) > 2 else ""
    return ""


def _хости_крамниць(оф):
    """{магазин: {хости, з яких ця крамниця віддає фото у фіді}}.

    ЧОМУ НЕ ПОРІВНЯННЯ З КЛЮЧЕМ КРАМНИЦІ (виміряно на `каталог_повний.xml`).
    Ключ `магазин` — це сам домен (`giardini-shoes.com`), і в 44 крамницях із 47
    фото лежать рівно на ньому. Але три крамниці віддають знімки з чужого CDN:
    `yakfaino.com` — з `yakfaino.fra1.cdn.digitaloceanspaces.com`,
    `e-c.storage.googleapis.com` і `res2.weblium.site` (жодного фото з власного
    домену), `maryline.ua` — половину з `maryline-strapi-storage…`,
    `natalibolgar.com` — два знімки з `widgets.natalibolgar.com`. Звірка з ключем
    назвала б їхні власні кадри чужими. Тому «домен крамниці» тут — те, чим його
    робить сам фід: множина хостів, з яких ця крамниця вже віддає картинки.

    ЩО ЦЕ ЛОВИТЬ. На цьому каталозі — нічого: усі 12 200 кадрів збагачення
    стоять на хості своєї крамниці, 0 чужих. Перевірка лишається названою межею
    запасного шляху: збій жнив або сестринська гілка, що підклала кадр з іншої
    адреси, не дійде до картки мовчки.
    """
    д = {}
    for o in оф:
        м = o.get("магазин") or str(o.get("id") or "").split("@")[-1]
        н = д.setdefault(м, set())
        for x in (o.get("фото") or []):
            h = _хост_фото(x)
            if h:
                н.add(h)
    return д


def _спільні_фото(оф):
    """{магазин: {файл: на скількох РІЗНИХ товарах крамниці він стоїть}}.

    Рахується з того самого каталогу, що вже прочитаний для карток, — іншого
    входу правило не має й не просить (офлайн, детерміновано). Назва товару тут
    — одиниця «це та сама річ»; коли назви нема, за неї править id, тобто річ
    рахується сама за себе.
    """
    наз = {}
    for o in оф:
        м = o.get("магазин") or str(o.get("id") or "").split("@")[-1]
        т = (o.get("назва") or str(o.get("id") or "")).strip().lower()
        д = наз.setdefault(м, {})
        for ф in {_файл_фото(x) for x in (o.get("фото") or []) if x}:
            д.setdefault(ф, set()).add(т)
    return {м: {ф: len(т) for ф, т in д.items()} for м, д in наз.items()}


