# замшевий чобіт, тобто те, що жінка й купує).
ФОРМИ_МЕНШЕ = 3        # менш ніж стільки кадрів із відомим розміром — не судимо
ФОРМА_НЕ_ДОРОЖЧА = 2   # у скільки разів меншим може бути кадр, заради якого
                       # відступає інакший формою


def _форма_меншини(кадри):
    """Індекси кадрів, чия форма відрізняється від більшості кадрів ЦІЄЇ речі.

    Порожньо, коли судити нема по чому: менш ніж `ФОРМИ_МЕНШЕ` кадрів із
    відомим розміром, або більшості нема (рівний поділ). «Більшість» тут —
    строга: понад половину кадрів із відомою формою, інакше меншиною можна
    назвати будь-яку з двох рівних груп. Обидві межі — у блоці над функцією.
    """
    проп = [_пропорція_фото(u) for u in кадри]
    форми = [None if p is None else round(p, 2) for p in проп]
    відомі = [f for f in форми if f is not None]
    if len(відомі) < ФОРМИ_МЕНШЕ:
        return set()
    лічба = {}
    for f in відомі:
        лічба[f] = лічба.get(f, 0) + 1
    дом, н = max(лічба.items(), key=lambda kv: (kv[1], -kv[0]))
    if н * 2 <= len(відомі):
        return set()
    більшість = max((_площа_фото(u) or 0)
                    for u, f in zip(кадри, форми) if f == дом)
    return {i for i, f in enumerate(форми)
            if f is not None and f != дом
            and більшість * ФОРМА_НЕ_ДОРОЖЧА >= (_площа_фото(кадри[i]) or 0)}


