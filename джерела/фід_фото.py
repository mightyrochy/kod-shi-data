# Тобто код доводив «це не фото цієї речі» рівно для ока й не доводив того
# самого для ВИМІРУ.
# ВИМІРЯНО на `каталог_повний.xml` (12 426 оферів, збагачення 12 223): кадр
# збагачення САМ є спільним файлом у 1 053 речах (8,5 %) — brenda 318/366,
# miraton 113/113, giardini-shoes 60/339, alot 59/393, 25union 52/369,
# kasandra 51/280, sezone 49/256, emmeliedelage 48/276, maryline 47/95,
# solmar 44/117. З них 477 ідуть аркою (власних фото фіду теж нема), 576
# показують власне фото, але колір/крій/довжину виміряно на чужому кадрі.
# ПОРІГ ТУТ НЕ ВИГАДУЄТЬСЯ ЗАНОВО: це та сама `СПІЛЬНЕ_ФОТО_ТОВАРІВ` з її
# власним виміром вище. Правило одне — читачів у нього два.
ЧОМУ_СПІЛЬНА = "кадр збагачення — спільна картинка крамниці, не фото цієї речі"


def спільна_картинка(файл, спільні):
    """На скількох РІЗНИХ товарах крамниці стоїть цей файл, коли їх уже
    `СПІЛЬНЕ_ФОТО_ТОВАРІВ` і більше; `None` — поки знімок ще пояснюється
    варіантами однієї моделі, тобто поки він ще фото цієї речі.

    Приймає ФАЙЛ (`_файл_фото`), а не адресу: обидва читачі вже групують знімки
    за файлом, і другий розбір адреси тут був би другим способом назвати те саме.
    `спільні` — словник ОДНІЄЇ крамниці з `_спільні_фото`; речі без знімків у
    ньому дають `.get(…, 1)`, тобто «стоїть сам за себе».
    """
    н = спільні.get(файл, 1) if файл else 1
    return н if н >= СПІЛЬНЕ_ФОТО_ТОВАРІВ else None


def чужий_кадр(url, спільні):
    """Названа причина, чому цей кадр — не фото цієї речі; `None` — коли він її.

    Той самий предикат, що в `спільна_картинка`, але з адреси й зі словами: читач
    каталогу кладе цей словник у запис (`чуже_фото`), а суд і картка цитують його
    жінці. Мовчазне `False` тут було б рівно тією тишею, від якої лікують: запис
    без кольору, і ніде не сказано, ЧОМУ його нема (CLAUDE.md п.4).
    """
    ф = _файл_фото(url) if url else None
    н = спільна_картинка(ф, спільні) if ф else None
    return dict(файл=ф, товарів=н, чому=ЧОМУ_СПІЛЬНА) if н else None
