import re


# ── ЧИЄ ЦЕ ФОТО Й ЯКОГО ВОНО РОЗМІРУ (21.09.2026, рядок 118 дошки) ──────────
# Власник побачив на картці «Слінгбеки бежеві NELA» логотип «EMMELIE DELAGE», а
# під «Сумка жіноча LADIES BAG ISLA» — чорну туфлю. Обидва знімки прийшли з
# `фото[0]` фіду, і обидва — НЕ фото цієї речі. Два незалежні дефекти, і обидва
# видно офлайн, у самому каталозі:
#   (а) перше фото багатьох крамниць — службова картинка (логотип, банер меню),
#       спільна на сотні карток;
#   (б) кадр жнив не впізнавався, бо крамниця віддає ТОЙ САМИЙ файл у різних
#       розмірах: у фіді `/23/400x600l95nn0/…-27391149827787.webp`, у збагаченні
#       `/23/1200x1600l95nn0/…-27391149827787.webp`. Звірка цілим рядком не
#       збігалась, і картка падала назад на фото[0], тобто на логотип.
# Три функції нижче — це весь офлайновий апарат для обох: ЯК називається файл
# (без хоста й розміру), ЯКИЙ він завбільшки і СКІЛЬКИ різних товарів крамниці
# його несуть. Мережі тут нема й не буде: `позначити_заглушки` (мережевий
# детектор жнив) лишається окремим шаром і цього не заміняє.
_РОЗМІР_СЕГМЕНТ = re.compile(r"^(\d{2,4})x(\d{2,4})(?![0-9x])", re.I)
_РОЗМІР_ХВІСТ = re.compile(r"[.\-_](\d{2,4})x(\d{2,4})(?=\.(?:webp|jpe?g|png))", re.I)
# Розмір, ПРИКЛЕЄНИЙ ДО ПОЧАТКУ ІМЕНІ ФАЙЛА, а не окремою текою (23.09.2026,
# рядок 143 дошки): `…/webp_cache/1740x2280q90-000211588_1_.webp` — miraton.
# Хвіст після розміру може нести якість (`q90`) чи профіль (`l95nn0`), а далі
# мусить стояти `-` або `_` і НЕПОРОЖНЄ ім'я. Крапка роздільником НЕ береться:
# у skripka лежить файл, який так і зветься — `1500x02.jpg`, і зняття «префікса»
# по крапці лишило б від нього саме `jpg` (виміряно: 2 адреси на каталозі).
_РОЗМІР_ПРЕФІКС = re.compile(r"^(\d{2,4})x(\d{2,4})(?![0-9x])[a-z0-9]*[-_](?=.)", re.I)


def _файл_фото(url):
    """Ім'я файла картинки без хоста й без сегмента розміру — «той самий знімок».

    ЧОМУ НЕ ГОЛЕ БАЗОВЕ ІМ'Я, А ШЛЯХ (виміряно на `каталог_повний.xml`, 12 405
    речей). Наряд просив звіряти базове ім'я файла; на каталозі його самого
    НЕ ВИСТАЧАЄ: у частини крамниць ім'я — лічильник усередині теки товару
    (`…/products/3557/1-1000x1500.webp` — dolcedonna, `…/25.10.25/43-293x440.webp`
    — brenda, `…/res/<uuid>/original` — yakfaino), тож «1-1000x1500.webp» спільне
    для всього каталогу крамниці. Відсів за голим іменем лишив би без знімка
    1 626 речей замість 1 405: 221 річ утратила б ВЛАСНЕ фото. На кадрі жнив
    обидва ключі дають те саме — зі 1 180 речей, де кадр упізнається лише після
    зняття розміру, шлях збігається у 1 179.

    ХОСТ ВІДКИНУТО як названа обережність, а не як виміряний виграш: жнива й фід
    можуть ходити різними адресами (123 речі вже несуть фото з кількох хостів),
    але на ЦЬОМУ каталозі хост не міняє нічого — усі 1 179 кадрів збігаються й з
    ним, і відсів дає ті самі 1 405 речей.

    ОСТАННІЙ СЕГМЕНТ — ІМ'Я, І ВІН НЕ ВИКИДАЄТЬСЯ ЦІЛКОМ (23.09.2026, рядок 143
    дошки). Доти відсів «сегмент, що починається з розміру» ішов по ВСІХ
    сегментах, зокрема по імені файла, — і в miraton
    `…/webp_cache/1740x2280q90-000211588_1_.webp` давав ключ `upload/webp_cache`
    на ВСІ 113 речей крамниці. Далі з цього виходило, що знімок «стоїть на 113
    товарах», тобто службова картинка, і всі живі webp крамниці випадали з
    картки; лишався `…/iblock/…/000211588_1_.resize1.jpg`, який крамниця вже не
    віддає (404 на всіх 113). Тепер розмір знімається з ІМЕНІ префіксом
    (`_РОЗМІР_ПРЕФІКС`), а не разом з іменем.
    ВИМІРЯНО на `каталог_повний.xml` (12 405 речей, 109 453 адреси): ключ
    змінився у 1 102 адрес трьох крамниць — natalibolgar 874
    (`…/iblock/d31/100x150q100-88.webp` → `…/iblock/d31/88.webp`), miraton 226,
    skripka 2 (`…/2026/05/1500x02.jpg`, доти зрізане до теки). Різних файлів
    стало 65 463 замість 65 315; кадр жнив упізнається в тих самих 11 201
    речах, із них 1 179 лише після зняття розміру — обидва числа не зрушили.
    """
    u = str(url or "").split("?")[0]
    ч = u.split("/")
    if u.lower().startswith(("http://", "https://")) and len(ч) > 3:
        ч = ч[3:]
    # ОСТАННІЙ СЕГМЕНТ — ЦЕ ІМ'Я, А НЕ ТЕКА (23.09.2026, рядок 143). Доти
    # той самий вираз ішов по ВСІХ сегментах, і ім'я, яке ПОЧИНАЄТЬСЯ з
    # розміру, викидалось цілком; див. блок над `_РОЗМІР_ПРЕФІКС`.
    імя = _РОЗМІР_ПРЕФІКС.sub("", ч[-1]) if ч else ""
    ч = [c for c in ч[:-1] if not _РОЗМІР_СЕГМЕНТ.match(c)] + [імя]
    return _РОЗМІР_ХВІСТ.sub("", "/".join(ч)).lower()


def _площа_фото(url):
    """Площа знімка в пікселях, ЯКЩО розмір зашитий у шлях; інакше `None`.

    Дві форми, обидві взяті з каталогу: сегмент шляху
    (`/400x600l95nn0/` → 240 000, `/33x50l80nn0/` → 1 650) і хвіст імені файла
    (`img_0414-copy_1.330x300.jpg`, `DSC07956-150x225.webp`). Розмір несуть
    58 446 із 109 453 картинок (53,4 %); у 5 126 речей його мають усі знімки, у
    6 080 — жоден.

    `None` — це «не знаю», а НЕ «мале». Різниця тут вирішальна: у 1 199 речей
    частина знімків має розмір у шляху, а частина ні (`vmma`: головний кадр
    `DSC05271.jpeg` без розміру, решта — мініатюри 150×225). Якби «не знаю»
    рахувалось нулем, картка обміняла б головний кадр на мініатюру іншого.
    """
    u = str(url or "").split("?")[0]
    for с in u.split("/"):
        м = _РОЗМІР_СЕГМЕНТ.match(с)
        if м:
            return int(м.group(1)) * int(м.group(2))
    м = _РОЗМІР_ХВІСТ.search(u)
    return int(м.group(1)) * int(м.group(2)) if м else None


