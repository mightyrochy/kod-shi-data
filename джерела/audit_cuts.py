# -*- coding: utf-8 -*-
"""Аудит таблиці КРОЇ проти опублікованих мінімумів носіння (тема-1 §17.1–17.2).

Питання одне: чи є в таблиці крої, які на РЕАЛЬНОМУ тілі дають припуск нижчий за
мінімум, з яким полотняну річ узагалі можна вдягнути. Якщо є — система пропонує
речі, що не застібаються, і жодне правило цього не бачить.
"""
import silhouette as СЛ
import fit as ПС

# Тіла на межах обслуговуваного діапазону + медіана
ТІЛА = [("мала",    dict(плечі=98,  груди=80,  талія=64, стегна=86),  158),
        ("медіана", dict(плечі=112, груди=94,  талія=74, стегна=100), 164),
        ("велика",  dict(плечі=128, груди=118, талія=104, стегна=124), 170)]

РІВНІ = ["плечі", "груди", "талія", "високе_стегно", "стегна", "щиколотка"]


def прогін():
    провали, пропущено = {}, {}
    for назва, обх, зріст in ТІЛА:
        t = ПС.тіло(зріст, обх)
        ш_тіла = {nm: w for nm, _, w in t["профіль"]}
        for крій in СЛ.КРОЇ:
            # РІД КРОЮ (тема-3: єдиний операційний біт фабричного шару). Мінімум
            # носіння опубліковано для ПОЛОТНА. Крій, що існує лише у трикотажі, під
            # нього не підпадає взагалі — доти половина цього вироку була шумом:
            # bodycon із −2.0 см потрапляв у список разом зі справжніми дефектами.
            рід = СЛ.рід_за_кроєм(крій)
            if рід == "трикотаж":
                пропущено.setdefault(крій, "лише трикотаж — опублікований мінімум "
                                            "носіння не діє (тема-1 §17.1)")
                continue
            for рів in РІВНІ:
                мін, опубл, _ = СЛ.мінімум_носіння(рів)
                if мін is None: continue
                w, _дж = СЛ.ширина_крою(крій, рів, lambda r: ш_тіла.get(r))
                if w is None or not ш_тіла.get(рів): continue
                # чи цей крій узагалі задає цей рівень (а не тягне крайнє значення)
                к = СЛ.КРОЇ[крій]
                задані = (к.get("ease") or к.get("форма") or {})
                if рів not in задані: continue
                припуск_см = (w - ш_тіла[рів]) * 3.141592653589793
                dc = припуск_см - мін
                if dc < 0:
                    провали.setdefault((крій, рів), []).append(
                        (назва, round(припуск_см, 1), round(мін, 1), round(dc, 1), опубл))
    return провали, пропущено


if __name__ == "__main__":
    п, пропущено = прогін()
    print("КРОЇ, ЩО ДАЮТЬ ПРИПУСК НИЖЧЕ МІНІМУМУ НОСІННЯ")
    print("=" * 78)
    if not п:
        print("  нема")
    for (крій, рів), рядки in sorted(п.items()):
        скільки = len(рядки)
        опубл = рядки[0][4]
        print(f"  {крій:16s} на «{рів}»: нижче мінімуму на {скільки}/{len(ТІЛА)} тілах"
              f"{'' if опубл else '  [мінімум ПЕРЕНЕСЕНИЙ, не опублікований]'}")
        for назва, пр, мін, dc, _ in рядки:
            print(f"       {назва:8s} припуск {пр:5.1f} см при мінімумі {мін:4.1f} "
                  f"-> дефіцит {-dc:4.1f} см")
    print("=" * 78)
    усього = len(СЛ.КРОЇ)
    биті = {k for k, _ in п}
    непевні = {k for k in СЛ.КРОЇ if СЛ.рід_за_кроєм(k) == "обидва"} & биті
    print(f"кроїв у таблиці: {усього}")
    print(f"  не перевіряються (лише трикотаж): {len(пропущено)} — {sorted(пропущено)}")
    print(f"  з дефіцитом хоч на одному орієнтирі: {len(биті)}")
    print(f"    з них крої роду «обидва» — вирок УМОВНИЙ, доки фід не дав склад: "
          f"{len(непевні)} — {sorted(непевні)}")
    певні = биті - непевні
    print(f"    крої, що бувають ЛИШЕ полотняними -> дефект БЕЗУМОВНИЙ: "
          f"{len(певні)} — {sorted(певні)}")
