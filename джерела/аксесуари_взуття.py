def халява_см(р, t):
    """Рівень халяви (порядкова мітка з фіду) → висота над підлогою НА ЦЬОМУ ТІЛІ.

    ЧОМУ ЦЕ ТУТ, А НЕ У ФІДІ: «щиколотка / литка / коліно» — це РІВНІ ТІЛА, і в
    сантиметрах вони різні на різних зростах. Фід віддає мітку, тіло дає число. Це і є
    вимога корпусу «ярлик — лише маршрутизація, рішення на виміряному»: мітка не
    вирішує нічого сама, вона лише вказує, який рівень профілю брати.

    Явна `халява_см` у речі перемагає виведену: якщо магазин назвав висоту, вона
    вимір, а не переклад.
    """
    if р.get("халява_см") is not None:
        return float(р["халява_см"]), "названо в картці"
    рівень = р.get("халява_рівень")
    if рівень is None or not t or not t.get("висоти"):
        return None, None
    y = t["висоти"].get(рівень)
    if y is None:
        return None, None
    return float(y), "рівень «%s» на профілі цього тіла (%.0f см)" % (рівень, y)


def поділ_см(р, t):
    """Висота подолу над підлогою НА ЦЬОМУ ТІЛІ — тим самим прийомом, що халява.

    ⚠ ДРУГА ПОЛОВИНА ПРАВИЛА НЕ МАЛА ВХОДУ (виміряно 17.09.2026). Тут стояло
    `min(верх_см, низ_см)`, і обидва поля у фіді порожні: `аудит/audit_feed_поля`
    так і пише — «краї на нозі рахуються з `верх_см`/`низ_см`, а вони у фіді 0 %».
    Отже з двох обʼєктів K-SHO-11 («халява й поділ — одне правило з різними
    обʼєктами») живим був РІВНО ОДИН, і правило, яке саме себе означує через пару,
    працювало на половині пари.
    А мітка довжини у фіді Є, і повна: `feed.довжина_речі` віддає РІВЕНЬ ТІЛА на
    100 % низів і суконь, із них не-порожній — на 1 778 із 3 664 (48.5 %): «литка»
    634, «максі» 601, «міні» 501, «коліно» 40. Рівень у сантиметри переводить
    профіль — рівно так, як це вже робить `халява_см` для халяви, і рівно те, чого
    вимагає корпус правила: «ярлик — лише маршрутизація, рішення на виміряному».

    Явне число в картці перемагає виведене — та сама умова, що в `халява_см`.
    """
    явний = (min(р["верх_см"], р["низ_см"])
             if р.get("верх_см") is not None and р.get("низ_см") is not None else None)
    if явний is not None:
        return float(явний), "поділ речі (верх_см/низ_см картки)"
    рівень = _рівень_подолу(р)
    if рівень is None or not t or not t.get("висоти"):
        return None, None
    y = t["висоти"].get(рівень)
    if y is None:
        return None, None
    return float(y), "довжина «%s» на профілі цього тіла (%.0f см)" % (рівень, y)


def халява_і_поділ(t, речі, вікно=None):
    """K-SHO-11. Правило халяви й правило подолу — ЦЕ ОДНЕ ПРАВИЛО З РІЗНИМИ ОБʼЄКТАМИ.

    ЩО ЦЕ МІНЯЄ (before/after). before — довжина оцінюється за ЯРЛИКОМ («міді», «міні»),
    а халява й поділ живуть у різних правилах. after — обидва краї міряються проти
    ВИМІРЯНОЇ найширшої точки литки ЦІЄЇ людини тією самою функцією; ярлик стає лише
    маршрутизацією. Корпус це вже вимагає для тіла («ярлики фігури як одиниця рішення» —
    заборонено); тут вимога поширюється на взуття й поділ.

    ДРУГИЙ КРАЙ, ЯКОГО СИСТЕМА НЕ БАЧИЛА: «спідниця стирчить з-під пальта» — це ДВА
    КРАЇ ПОРУЧ, а не один поганий край. Верхній шар мусить бути або довшим, або помітно
    коротшим; збіг у межах кількох сантиметрів — відмова.

    ДЕ ЛАМАЄТЬСЯ, І ЦЕ ГОЛОВНЕ ПРО ЦЕ ПРАВИЛО: «найширша точка литки» вимагає ВИМІРУ
    ЛИТКИ, якого ні фото, ні анкета не дають. Без нього профіль спирається на
    популяційний шаблон — тобто на ярлик, який правило само й забороняє. Тому тут
    ДВІ ГІЛКИ, і друга не мовчить: коли на нозі немає локального максимуму, правило
    виходить ПИТАННЯМ із названим блокером, а не тишею.
    ФОЛЬКЛОРНІ КОНСТАНТИ ДЖЕРЕЛА, ЯКІ СЮДИ НЕ ЗАВЕДЕНО: «+5 кг візуально» — риторика,
    не вимір; «1/3 : 2/3» уже стоїть у корпусі як невиміряне правило третин.
    """
    if not t or not t.get("профіль"):
        return []
    проф, зріст = t["профіль"], t["зріст"]
    зн = []
    # ── ГІЛКА 2 (спершу, бо вона визначає, чи гілка 1 узагалі має сенс) ──────
    # Чи існує на нозі локальний максимум? Якщо ні — жоден краєвий вимір нижче
    # стегон нічого не скаже, і сказати це треба вголос.
    ноги_є = any(ПС.край_проти_локального(проф, y)["локальний_максимум"]
                 for y in (0.18 * зріст, 0.20 * зріст, 0.22 * зріст, 0.25 * зріст))
    краї_ніг = []
    for р in речі:
        сл = р.get("слот")
        if сл == "взуття":
            якщо, звідки = халява_см(р, t)
        elif сл in ("низ", "сукня", "комплект", "верхній_шар"):
            якщо, звідки = поділ_см(р, t)
        else:
            continue
        if якщо is not None:
            краї_ніг.append((р, float(якщо), звідки))
    if краї_ніг and not ноги_є:
        # ── ДВІ ПРИЧИНИ ОДНОГО МОВЧАННЯ, І ВОНИ НЕ ОДНЕ Й ТЕ САМЕ ────────────
        # Максимуму на нозі нема або тому, що литку НЕ МІРЯЛИ (профіль стоїть на
        # популяційному шаблоні), або тому, що її ВИМІРЯЛИ і на ЦЬОМУ тілі вона
        # просто не найширша точка — литка вужча за коліно є найтиповішим живим
        # випадком. Доти ремонт казав «обхват литки стрічкою — один вимір» в
        # обох, тобто просив вимір, який людина щойно дала: та сама «неправда в
        # матеріалі, на якому модель вирішує», проти якої стоїть fit.py:206-222.
        # Джерело істини лежить поруч і не вигадується тут: `fit.тіло` пише
        # «ширина:литка» у `виміряні_рівні` рівно тоді, коли обхват прийшов
        # виміром, а не шаблоном.
        виміряно = "ширина:литка" in (t.get("виміряні_рівні") or ())
        if виміряно:
            суть = ("литку виміряно, і на цьому тілі вона не є локальним максимумом — "
                    "краї на нозі не мають з чим порівнюватись")
            чому = ("ціль правила — край НИЖЧЕ найширшої точки литки, а не «міді взагалі». "
                    "Литка ЦІЄЇ людини виміряна і вужча за коліно, тож локального максимуму "
                    "на нозі не існує, і край нема з чим зіставити. Це вимір, а не брак "
                    "входу: питання тут про саме правило, а не про анкету")
            ремонт = ("міряти нема чого — вимір уже є. На цьому тілі довжину халяви й "
                      "подолу вирішують інші правила, а K-SHO-11 мовчить ЗА ВИМІРЮВАННЯМ")
            ламається = ("вимір є, і правило все одно не виходить: «найширша точка литки» "
                         "існує не на кожній нозі. Це межа правила, а не дірка входу")
            джерело = "вимір (литка виміряна; локального максимуму на нозі нема)"
            слід = "литку виміряно, максимуму на нозі нема"
        else:
            суть = "найширшої точки литки в профілі не існує — краї на нозі не міряються"
            чому = ("ціль правила — край НИЖЧЕ найширшої точки литки, а не «міді взагалі». Але в "
                    "профілі цієї людини литка вужча за коліно, тож локального максимуму на нозі "
                    "нема, і порівнювати край нема з чим. Правило спиралося б на популяційну "
                    "середню — тобто стало б ЯРЛИКОМ, який само й забороняє")
            ремонт = ("обхват литки стрічкою — один вимір, і обидва краї (халява й поділ) "
                      "починають рахуватись")
            ламається = ("вимір литки не дає ні фото, ні анкета в поточному вигляді; це "
                         "названий блокер, а не мовчазний прохід")
            джерело = "входу нема (обхват литки не виміряний)"
            слід = "локального максимуму на нозі нема"
        зн.append(dict(_зн("K-SHO-11", "питання", суть,
            sorted({(р.get("назва") or р.get("id")) for р, _, _ in краї_ніг}),
            чому, ремонт=ремонт, ламається=ламається),
            сила_нп=0.0, сила_нп_джерело=джерело))
        _СЛ.запис("K-SHO-11", слід, "халява_і_поділ",
                  значення="краї: %d" % len(краї_ніг), сила=0.0, напрям="черга, не провал")
    # ── ГІЛКА 1: халява й поділ — той самий вимір, що K-FIT-03 ───────────────
    elif краї_ніг:
        for р, край, звідки in краї_ніг:
            if not (0.0 <= край <= зріст):
                continue
            м = ПС.край_проти_локального(проф, край, вікно)
            if not (м["на_максимумі"] and м["важіль_є"]):
                continue
            лок = м["локальний_максимум"] or {}
            відрізки = ПС.вікно_краю(проф, край, вікно)
            # ── ІМЕНОВАНЕ ПРАВИЛО ГОВОРИТЬ, УЗАГАЛЬНЕННЯ МОВЧИТЬ ─────────────
            # Той самий розвʼязок, яким цей модуль уже зняв дубль K-EDG-01 ↔
            # K-ACC-04 (див. коментар до `НОСІЇ_КРАЮ`): де є іменоване правило з
            # власним джерелом, воно й несе знахідку, а узагальнення лишається
            # для обʼєктів без власного правила.
            # ХАЛЯВА МАЄ ВЛАСНЕ ПРАВИЛО — K-SHO-05 («халява чобота — ТОЧКА
            # ЗАВЕРШЕННЯ; халява на найширшій частині литки — класичний провал;
            # машинно-перевірне проти карти зон», тема-4, сила `strong`). Воно
            # стояло в корпусі з мітками «виконуваний: так · у коді: —»: механізм
            # працював, і приписаний був УЗАГАЛЬНЕННЮ. K-SHO-11 лишається на
            # подолі — на тому обʼєкті, заради якого він і каже «одне правило з
            # різними обʼєктами».
            # ДВОХ ЗНАХІДОК З ОДНОГО ВИМІРУ ТУТ НЕ ЗʼЯВЛЯЄТЬСЯ: ID один на край,
            # обирається за обʼєктом. Саме цього вимагає Н-V15-035 («дубль із
            # різними кодами з ОДНОГО виміру»).
            халявний = р.get("слот") == "взуття"
            обʼєкт = "халява" if халявний else "поділ"
            прав_краю = "K-SHO-05" if халявний else "K-SHO-11"
            сила_нп = round(min(1.0, 0.5 + 0.5 * (1.0 - (м["близькість"] or 0.0) / 0.03)), 2)
            зн.append(dict(_зн(прав_краю, "soft",
                "%s «%s» на найширшій точці (%s)" % (обʼєкт, р.get("назва") or р.get("id"),
                                                     лок.get("рівень", "?")),
                [р.get("назва") or р.get("id")],
                ("халява — це ТОЧКА ЗАВЕРШЕННЯ, і вона сіла на найширшу частину литки: "
                 "класичний провал, названий джерелом прямо. Ботфорти й ботильйони "
                 "домовляються з кожною довжиною подолу по-різному, тож рішення тут одне на "
                 "пару «халява + поділ»" if халявний else
                 "край на найширшій точці програє, чи то край халяви, чи то край подолу, чи то "
                 "межа колготок — це ОДНЕ правило з різними обʼєктами")
                + "; край на %.0f см (%s), максимум на %.0f см"
                % (край, звідки or "джерело не назване", лок.get("см", край)),
                ремонт=(["зсунути край НИЖЧЕ найширшої точки: %s"
                         % ", ".join("%.0f–%.0f см" % s for s in відрізки[:2])]
                        if відрізки else ["зазору для зсуву в межах цієї моделі нема"]),
                ламається="зазору («наскільки нижче») джерело не дає: 1 см і 10 см не те "
                          "саме, а правило їх не розрізняє. Отже — ПОРЯДОК КАНДИДАТІВ, не "
                          "гейт. «+5 кг візуально» з того самого джерела — риторика, не "
                          "вимір, і в код не заведена",
                поріг=0.03, вимір=м["близькість"] or 0.0),
                сила_нп=сила_нп,
                сила_нп_джерело="вимір (fit.край_проти_локального: близькість до опуклості)"))
            _СЛ.запис(прав_краю, "%s на найширшій точці" % обʼєкт, "халява_і_поділ",
                      значення="%.0f см" % край, сила=сила_нп, напрям="порядок, не гейт")
    # ── ДВА КРАЇ ПОРУЧ: ВИДАЛЕНО 26.08.2026, ВЛАСНИКА ЗМІНЕНО НА K-OUT-03 ───────
    # ТУТ БУВ ДУБЛІКАТ. Гілка міряла відстань між краєм верхнього шару й краєм
    # спідниці/сукні («спідниця стирчить з-під пальта») — і тема-11 завела K-OUT-03,
    # який міряє ТУ САМУ пару тим самим числом. Прогін на одному образі давав дві
    # знахідки: K-SHO-11 «стирчить на 2 см» і K-OUT-03 «краї майже збігаються: 2.0 см».
    #
    # ЧОМУ ЗНЯТО САМЕ ЦЮ, А НЕ ТУ (вимір покриття, не смак):
    #   випадок                        K-SHO-11        K-OUT-03
    #   пальто нижче на 2 см           ловить          ловить (+ K-OUT-43 ремонт)
    #   пальто ВИЩЕ на 2 см            МОВЧИТЬ         ловить  ← моя гілка однобока
    #   точний збіг                    МОВЧИТЬ         «питання»: записує спір джерел
    #   край із дефолту слота          рахує число     «питання»: вимір над заглушкою
    #   застібнуте, ховає повністю     ЛОВИТЬ ХИБНО    мовчить ← двох видимих країв нема
    # Нуль втрати покриття, мінус одне хибне спрацювання.
    #
    # І ПО СУТІ: K-SHO-11 — це «халява й поділ проти НАЙШИРШОЇ ТОЧКИ ЛИТКИ», один край
    # проти опуклості тіла. Пара країв між собою — інший обʼєкт, і в теми-11 під нього
    # чотири джерела, які СПЕРЕЧАЮТЬСЯ; K-OUT-03 записує спір замість обрати сторону,
    # а моя гілка сторону обирала мовчки. Це рівно те правило теми-10, яким я вже
    # знімав K-EDG-01 з халяви: де є іменоване правило з власним джерелом — говорить воно.
    return зн


