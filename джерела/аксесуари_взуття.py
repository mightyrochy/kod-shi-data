# закрита», якщо її тип не ловився окремо. Той самий клас дефекту, що вже двічі
# спійманий у цьому файлі: два модулі домовились про поле й не про форму значення.
# Нога гола на всьому, крім «максі»; старі слова лишені — на них стоять синтетичні
