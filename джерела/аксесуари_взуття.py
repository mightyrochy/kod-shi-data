# ⚠ СЛОВНИК ЗНАЧЕНЬ, А НЕ СПИСОК СИНОНІМІВ (17.09.2026). Тут стояло
# («міні», «міді», «укорочені»), а `feed.ДОВЖИНА_КЛЮЧІ` пише РІВЕНЬ ТІЛА:
