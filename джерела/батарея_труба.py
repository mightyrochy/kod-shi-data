"""ГЕЙТ E · ПРОГОНИ ЗІБРАНОГО ОБРАЗУ.

Друга половина труби: образ уже зібраний і йде через `pipeline.перевірити_образ`
(`прогін_зібраного`), кожна названа гілка перевіряється ізольовано
(`_перевірка_гілок`), інгест каталогу (`_прогін_фіду`), навмисні образи обома
суддями (`_навмисні_образи`, `_навмисні_від_моделі`) і сам ВИБІР — композитор
(`_прогін_композитора`). Речі синтетичні, вердикту людини нема: це доводить, що
правило ДОСЯЖНЕ, і не доводить, що воно ПРАВЕ.
"""

import колір_річ as _КОЛІР
from батарея_входи import СЦЕНИ_ОБРАЗУ, РИСИ_ОБРАЗУ, ЛЮДИНА_ТРИ_ВОЛОСИНИ
from батарея_образи import НАВМИСНІ, ЦІЛЬ_ОБРАЗУ, ПІДСТАВА_ШИРОКОГО_ШЛЯХУ, з_геометрією
from батарея_слід import знахідки_дерева, чеклістні_дерева

def прогін_зібраного():
    """ДРУГА ПОЛОВИНА ТРУБИ: образ уже зібраний. Повертає (слід, знахідки, гілки).

    ЧОМУ ЦЕ ОКРЕМА РУКА БАТАРЕЇ. Батарея вище викликає лише `bridge.виклик`, а це
    шлях ДО вибору речей: колірні вікна, бриф, палітри. Правила, які міряють
    РІЧ НА ТІЛІ (де закінчується край, чи ховає крій талію, чи не б'ється метал
    із підтоном), у ньому не мають входу — і гейт звітував їх як мертві. Тут
    зібраний образ проганяється через `pipeline.перевірити_образ`, і мертвість
    перестає означати «мій стенд його не викликав».

    ЧЕСНА МЕЖА: речі синтетичні, вердикту людини нема. Це доводить, що правило
    ДОСЯЖНЕ, і не доводить, що воно ПРАВЕ.
    """
    import trace as СЛ, pipeline, fit as ПС, areas, colorspace as cs
    СЛ.почати()
    сл, зн, спільні, чек = set(), set(), set(), {}
    F = cs.features(*РИСИ_ОБРАЗУ)
    тіло = ПС.тіло(168, dict(плечі=98, груди=92, талія=72, стегна=100,
                             коліно=35.0, литка=36.0, щиколотка=22.0))
    # areas хоче ПРОФІЛЬ (список (назва, см, ширина)), не dict тіла — це різні
    # структури, і плутанина між ними коштувала першому прогону KeyError.
    профіль = areas.профіль_тіла(168, dict(плечі=98, груди=92, талія=72, стегна=100))
    H = areas.висоти_рівнів(168)   # висоти всіх рівнів, з лінією плеча (у профілі її нема — вузол без ширини)
    сирі = [dict(id="джемпер", верх_см=H["лінія_плеча"], низ_см=H["талія"], припуск="relaxed"),
            dict(id="прямі штани", верх_см=H["талія"], низ_см=H["щиколотка"]),
            dict(id="лофери", верх_см=H["щиколотка"], низ_см=H["підлога"], припуск="relaxed")]
    гео = {g["id"]: g for g in areas.образ_з_геометрії(профіль, сирі)}
    гекси = {"джемпер": ("верх", "#8fa3b0"), "прямі штани": ("низ", "#4a6285"),
            "лофери": ("взуття", "#a9825c")}
    речі = [dict(id=i, слот=гекси[i][0], hex=гекси[i][1], площа=гео[i]["площа"],
                 near=гео[i]["near"], джерело_площі="геометрія",
                 верх_см=r["верх_см"], низ_см=r["низ_см"],
                 припуск=r.get("припуск", "straight"))
            for i, r in ((x["id"], x) for x in сирі)]
    for нагода, темп in (("робота", 5.0), ("побачення", 19.0)):
        try:
            _в = pipeline.перевірити_образ(F, речі, dict(нагода=нагода, смуга_погоди=темп), тіло=тіло)
        except Exception as _e:
            import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
            if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
            continue
        _вл, _сп = знахідки_дерева(_в)
        зн |= _вл
        спільні |= _сп
        for _r, _ст in чеклістні_дерева(_в).items():
            чек.setdefault(_r, set()).update(_ст)
    _прогін_фіду()
    _навмисні_образи(F, тіло, H, зн, спільні, чек)
    _навмисні_від_моделі(F, тіло, H, зн, спільні, чек)
    _прогін_композитора(F, тіло)
    # Друга людина композитора — три відтінки волосся (`ЛЮДИНА_ТРИ_ВОЛОСИНИ`): K-PAL-07 («колор_блок»)
    # живе лише на різнотоновому волоссі, а людина `РИСИ_ОБРАЗУ` має один голос волосся. Композитор
    # дешевий (одна збірка), і саме він вів K-PAL-07 у сукупному сліді батареї до заміни людини.
    try:
        import bridge
        _прогін_композитора(bridge._збірка(ЛЮДИНА_ТРИ_ВОЛОСИНИ)[0], тіло)
    except Exception as _e:
        import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
        if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
    # ЦИТАТА ДЖЕРЕЛА — НЕ СЛІД.
    # `прогін` і `прогін_від_моделі` відкидають записи з `напрям == НАПРЯМ_ЦИТАТА`, а ця нога
    # брала `СЛ.ід_у_сліді()` — усі записи підряд. Відколи зібраний образ проходить через
    # `palettes.прийоми`, кожен активний прийом лишає, крім власного K-PAL-NN, ще й записи
    # для кодів з поля `джерело`, і вони тут ставали «слідом»: K-COL-08 («розміщення») із
    # «без сліду» ставав «лише слід», R-CHEV-15 (Chevreul у тому ж `джерело`) — теж, хоч
    # жодне з двох правил там нічого не судило. Слід — лише те, що правило спрацювало.
    сл |= {з["правило"] for з in СЛ.зібрати()
           if з["правило"] and з.get("напрям") != СЛ.НАПРЯМ_ЦИТАТА} | зн
    # ІЗОЛЯЦІЙНА ПЕРЕВІРКА ВХОДИТЬ У ЗВІТ: `_перевірка_гілок`
    # була написана й НЕ викликалась нізвідки — рівно той гріх, у якому цей файл
    # звинувачує корпус («реалізоване й не під'єднане не міняє жодного рішення»).
    # Перший же під'єднаний прогін зловив: образ-ціль K-INT-04 не будить ВЛАСНУ
    # гілку — його ID у сукупному сліді приходив з іншого образу, і без ізоляції
    # це було невидимо.
    гілки = _перевірка_гілок(F, тіло, H)
    return dict(слід=сл, знахідки=зн, спільні=спільні - зн, чекліст=чек, гілки=гілки)


def _перевірка_гілок(F, тіло, H):
    """Чи ожила НАЗВАНА гілка кожного образу — по одному, ізольовано.

    Сукупний прогін зливає образи в один слід: ціль може спрацювати на чужому
    образі. Тут кожен образ проходить обидва входи судді сам, а поруч стоїть
    його ціль. Повертає (ціль, ожила, опис); шлях — `_гілки_зі_шляхом`.
    """
    return [(ціль, ожила, чому) for ціль, ожила, чому, _шлях in _гілки_зі_шляхом(F, тіло, H)]


def _шлях_ожила(ціль, слід, власні_2, сильні_2, також_1):
    """Шлях, яким ціль ожила, або None. Прийом лише того, що показується в продукті:
    власний запис сліду (цитата джерела не слід — її відкинуто в `слід`); інакше —
    шлях, названий поіменно в `ПІДСТАВА_ШИРОКОГО_ШЛЯХУ`, і лише він."""
    if ціль in слід:
        return "власний запис сліду"
    шлях = ПІДСТАВА_ШИРОКОГО_ШЛЯХУ.get(ціль, (None,))[0]
    if шлях == "власна знахідка другого входу" and ціль in власні_2 and ціль in сильні_2:
        return шлях
    if шлях == "також_правила першого входу" and ціль in також_1:
        return шлях
    return None


# Сцена батареї несе поряд зі сценарієм входи суду, що не є полями опису (`source`, `вето_покриття`, `жорстке_ні`):
# вони йдуть іменованими параметрами `перевірити_образ`, сценарій — одним описом.
_НЕ_СЦЕНАРІЙ = ("source", "вето_покриття", "жорстке_ні")


def _перевірити(pipeline, F, речі, с, тіло):
    return pipeline.перевірити_образ(F, речі, {к: v for к, v in с.items() if к not in _НЕ_СЦЕНАРІЙ}, тіло=тіло,
                                     **{к: с[к] for к in _НЕ_СЦЕНАРІЙ if к in с})


def _гілки_зі_шляхом(F, тіло, H):
    """(ціль, ожила, опис, шлях) по кожному образу; `шлях` — з `_шлях_ожила`."""
    import pipeline, trace as СЛ, знахідка as ЗН
    вих = []
    сцен = СЦЕНИ_ОБРАЗУ          # один список на дві руки — обґрунтування там
    import fit as _ПС   # тіло з пахом — той самий принцип двох тіл, що в _навмисні_образи
    тіло = _ПС.тіло(168, dict(плечі=98, груди=92, талія=72, стегна=100,
                              коліно=35.0, литка=36.0, щиколотка=22.0),
                    рівні_см={"пах": 75.6})
    import areas as _ОБЛ
    _проф = _ОБЛ.профіль_тіла(168, dict(плечі=98, груди=92, талія=72, стегна=100))
    for чому, речі in НАВМИСНІ(H):
        ціль = ЦІЛЬ_ОБРАЗУ(чому)
        речі = з_геометрією(речі, _проф)   # ворота площі, обґрунтування там
        СЛ.почати()
        також_1 = set()
        for с in сцен:
            try:
                _в = _перевірити(pipeline, F, [dict(r) for r in речі], с, тіло)
                також_1 |= знахідки_дерева(_в)[1]
            except Exception as _e:
                import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
                if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
                pass
        # Другий вхід суду — як у сукупному прогоні; лічба хроми живе в ньому.
        # Ненульова вага доводить дію; питання й нульове утримання доказом не є.
        _в = _образ_від_моделі(F, речі, тіло)
        власні_2 = знахідки_дерева(_в)[0]
        сильні_2 = {з["правило"] for _ш, з in ЗН.усі(_в)
                    if з.get("правило") and (з.get("сила_нп") or 0) > 0}
        # слід продукту без цитат джерела: цитата каже «правило названо в джерелі
        # чужої поради», а не «правило спрацювало»
        слід = {з["правило"] for з in СЛ.зібрати()
                if з["правило"] and з.get("напрям") != СЛ.НАПРЯМ_ЦИТАТА}
        if ціль is None:
            # образ заради ВХОДУ, а не заради названої цілі: перевіряти його
            # проти чужого ID означало б вигадати вердикт
            вих.append(("—", None, чому, None))
        else:
            шлях = _шлях_ожила(ціль, слід, власні_2, сильні_2, також_1)
            вих.append((ціль, шлях is not None, чому, шлях))
    return вих


def _прогін_фіду():
    """ПЕРШИЙ ЯРУС ТРУБИ, ЯКОГО БАТАРЕЯ НЕ МАЛА ЗОВСІМ.

    Батарея викликала міст (людина → вікна) і перевірку образу. Інгест каталогу —
    те, з чого труба ПОЧИНАЄТЬСЯ — не викликався ніде, тому правила шару фіду
    (R-FEED-*) не мали жодного шансу лишити слід. Вони не мертві: `run_outfit.py`
    ганяє їх наскрізно, і `audit_feed.py` їх регресує. Мертвим був цей ярус батареї.

    Фікстура — та сама, що в `run_outfit` (діалект Rozetka). Це доводить, що
    правило ДОСЯЖНЕ, і не доводить, що реальний магазин пише саме так.
    """
    import os as _os, tempfile, feed
    try:
        import run_outfit as ПО
        шлях = _os.path.join(tempfile.gettempdir(), "гейт_каталог.xml")
        # ── ТРЕТЯ ГІЛКА ЛАНЦЮГА ІДЕНТИЧНОСТІ НЕ МАЛА ВХОДУ (R-FEED-01) ────────
        # ЩО ЦЕ МІНЯЄ (правило 3). `feed._ключ_моделі` має чотири гілки, і третя —
        # «vendor + categoryId + стем назви» — вмикається лише коли нема НІ
        # `group_id`, НІ `article`/`vendorCode`/`model`. Фікстура `run_outfit`
        # ставить `article` КОЖНОМУ оферу, тож гілка не виконувалась жодного разу,
        # і гейт звітував R-FEED-01 мертвим. Це вимір фікстури, не правила.
        # ВХІД НЕ ВИГАДАНИЙ: це дослівно фейл-кейс, записаний у самому
        # `feed.py` — `ager_brief.xml`, де кожен РОЗМІР окремий офер без
        # group_id/article, id має форму <модель>_<варіант>, а назва однакова на
        # всі розміри (виміряно: 260 оферів = 124 дизайни). Тут та сама
        # форма трьома оферами: правило мусить звести їх в ОДНУ модель.
        _без_ключа = "".join("""
  <offer id="AG-771_%s" available="true">
    <name>Сукня трикотажна ягідна</name><categoryId>5</categoryId><price>1490</price>
    <vendor>Ager</vendor>
    <stock_quantity>2</stock_quantity><picture>https://x/ag771.jpg</picture>
    <param name="Колір"><value lang="uk">Бордовий</value></param>
  </offer>""" % р for р in ("S", "M", "L"))
        _xml = ПО._зібрати_xml().replace("</offers>", _без_ключа + "\n</offers>")
        open(шлях, "w", encoding="utf-8").write(_xml)
        import colorspace as _cs
        offers, _діаг = feed.читати_yml(шлях)
        каталог = []
        for o in offers:
            h = ПО._HEX.get(o.get("group_id"))
            if not h:
                continue
            каталог.append(dict(id=o["id"], group_id=o["group_id"], lab=_cs.hx(h),
                                впевненість=0.8, колір_назва=o["колір_назва"],
                                фото_ключ=(o["фото"] or [None])[0]))
        feed.лексикон(каталог, мін_n=2)
    except Exception as _e:
        import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
        if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
        pass


def _навмисні_образи(F, тіло, H, зн=None, спільні=None, чек=None):
    """Кожен образ — під названу гілку. Виняток гаситься навмисно: мета батареї —
    ДІСТАТИ гілки, а не впасти на першій, у якої бракує поля.

    `зн` — множина, у яку складаються ID, що вийшли ЗНАХІДКОЮ (Н-P17). Без неї
    сім навмисних образів давали лише слід: результат `перевірити_образ` тут
    викидався, і правило, яке на цих образах саме й судить річ, рахувалось
    трасою нарівні з процесовими.
    `спільні` — те саме для ID, названих полем `також_правила`; `чек` — для ID,
    названих пунктами тристанових чеклістів. Обидва канали доти викидались тут
    разом із рештою виходу, і саме на навмисних образах вони й народжуються:
    K-SIL-07 їде на знахідці K-COL-01 образу-колони, K-COMP-06 — на ремонті
    K-INT-04 образу трьох нейтралів.
    """
    import pipeline
    # ЗНАЙДЕНО ПЕРШИМ ЖЕ ПРОГОНОМ ЦІЄЇ БАТАРЕЇ: `вето_покриття` — це dict
    # {"зони": [...], "ноги_вище_см": N}, а не список. Список валив увесь виклик
    # AttributeError'ом на `вето.get`, і всі сім образів мовчки не доїжджали.
    # Мовчки — бо батарея гасить винятки, щоб дістати гілки, а не падати. Ціна
    # цього рішення названа тут: зламаний вхід виглядає рівно як мертве правило.
    сцен = СЦЕНИ_ОБРАЗУ          # той самий список, що в `_перевірка_гілок`
    # ДВА ТІЛА В БАТАРЕЇ — НЕ НЕДБАЛІСТЬ. Базова трійка (прогін_зібраного) іде на
    # тілі БЕЗ виміряного паху: там живе K-BOD-05-«питання» (правило-утримання).
    # Навмисні образи йдуть на тілі З пахом: там живе K-FIT-04 (вісь виміряна,
    # посадка пояса стає важелем). Одне тіло на всю батарею гасило б одне з двох —
    # обидва стани входу реальні, і система мусить жити в обох.
    import fit as _ПС
    тіло = _ПС.тіло(168, dict(плечі=98, груди=92, талія=72, стегна=100,
                              коліно=35.0, литка=36.0, щиколотка=22.0),
                    рівні_см={"пах": 75.6})
    import areas as _ОБЛ
    _проф = _ОБЛ.профіль_тіла(168, dict(плечі=98, груди=92, талія=72, стегна=100))
    # ── ДРУГА ЛЮДИНА: СИВЕ ВОЛОССЯ Й ЗРІСТ 158 (друге проходження) ────────────
    # ЩО ЦЕ МІНЯЄ (правило 3). Та сама причина, що й «два тіла — не недбалість»
    # вище, лише вхід інший: два правила живуть НЕ в речах і не в сцені, а в
    # ЛЮДИНІ, і на єдиній людині батареї їхня умова хибна завжди.
    #   · K-PAL-13 (сивина) — прийом `palettes.прийоми` умикається лише на
