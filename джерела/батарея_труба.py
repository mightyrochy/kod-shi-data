def _перевірка_гілок(F, тіло, H):
    """Чи ожила НАЗВАНА гілка кожного образу — по одному, ізольовано.

    ЧОМУ ОКРЕМО ВІД `_навмисні_образи`. Той прогін зливає всі сім образів в один
    слід, і в ньому не видно, чиє саме правило спрацювало: сім образів дають ~40
    ID, з яких сім цільових можуть бути будь-де. Тут кожен образ проганяється сам,
    і поруч стоїть його ціль. Це різниця між «батарея прогналась» і «гілка ожила».
    """
    import pipeline, trace as СЛ
    вих = []
    # `protocolized` — не косметика сценарію. ВИМІРЯНО: на `uncontrolled` стеля
    # надійності осі підтону = 0.15, і сила правила металу падає до 0.026 — нижче
    # підлоги 0.05 ЩЕ ДО того, як K-CLR-05 щось загасить. Тобто на некаліброваному
    # фото K-CLR-05 недосяжний ПРИНЦИПОВО: гасити нема чого. На `protocolized`
    # (впевненість 0.50) вимір дає 0.085 → з оливою 0.034 → рівно та гілка, яку
    # правило й описує. Це не підкручений вхід, а названа умова застосування:
    # правило працює лише там, де підтон узагалі виміряний.
    сцен = СЦЕНИ_ОБРАЗУ          # один список на дві руки — обґрунтування там
    import fit as _ПС   # тіло з пахом — той самий принцип двох тіл, що в _навмисні_образи
    тіло = _ПС.тіло(168, dict(плечі=98, груди=92, талія=72, стегна=100,
                              коліно=35.0, литка=36.0, щиколотка=22.0),
                    рівні_см={"пах": 75.6})
    import areas as _ОБЛ
    _проф = _ОБЛ.профіль_тіла(168, dict(плечі=98, груди=92, талія=72, стегна=100))
    for чому, речі in НАВМИСНІ(H):
        ціль = ЦІЛЬ_ОБРАЗУ(чому)
        речі = з_геометрією(речі, _проф)   # ворота площі, обґрунтування там
        СЛ.почати()
        for с in сцен:
            try:
                pipeline.перевірити_образ(F, [dict(r) for r in речі], тіло=тіло, **с)
            except Exception as _e:
                import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
                if _os.environ.get("ЛЮСТЕРКО_ТРАСА"): _tb.print_exc()
                pass
        if ціль is None:
            # образ заради ВХОДУ, а не заради названої цілі: перевіряти його
            # проти чужого ID означало б вигадати вердикт
            вих.append(("—", None, чому))
        else:
            вих.append((ціль, ціль in СЛ.ід_у_сліді(), чому))
    return вих


def _прогін_фіду():
    """ПЕРШИЙ ЯРУС ТРУБИ, ЯКОГО БАТАРЕЯ НЕ МАЛА ЗОВСІМ.

    Батарея викликала міст (людина → вікна) і перевірку образу. Інгест каталогу —
    те, з чого труба ПОЧИНАЄТЬСЯ — не викликався ніде, тому правила шару фіду
    (R-FEED-*) не мали жодного шансу лишити слід. Вони не мертві: `run_outfit.py`
    ганяє їх наскрізно, і `audit_feed.py` їх регресує. Мертвим був цей ярус батареї.

    Фікстура — та сама, що в `run_outfit` (діалект Rozetka). Це доводить, що
    правило ДОСЯЖНЕ, і не доводить, що реальний магазин пише саме так.
    """
    import os as _os, tempfile, feed
    try:
        import run_outfit as ПО
        шлях = _os.path.join(tempfile.gettempdir(), "гейт_каталог.xml")
        # ── ТРЕТЯ ГІЛКА ЛАНЦЮГА ІДЕНТИЧНОСТІ НЕ МАЛА ВХОДУ (R-FEED-01) ────────
        # ЩО ЦЕ МІНЯЄ (правило 3). `feed._ключ_моделі` має чотири гілки, і третя —
        # «vendor + categoryId + стем назви» — вмикається лише коли нема НІ
        # `group_id`, НІ `article`/`vendorCode`/`model`. Фікстура `run_outfit`
        # ставить `article` КОЖНОМУ оферу, тож гілка не виконувалась жодного разу,
        # і гейт звітував R-FEED-01 мертвим. Це вимір фікстури, не правила.
        # ВХІД НЕ ВИГАДАНИЙ: це дослівно фейл-кейс, записаний у самому
        # `feed.py` — `ager_brief.xml`, де кожен РОЗМІР окремий офер без
        # group_id/article, id має форму <модель>_<варіант>, а назва однакова на
        # всі розміри (виміряно 24.08.2026: 260 оферів = 124 дизайни). Тут та сама
        # форма трьома оферами: правило мусить звести їх в ОДНУ модель.
        _без_ключа = "".join("""
  <offer id="AG-771_%s" available="true">
    <name>Сукня трикотажна ягідна</name><categoryId>5</categoryId><price>1490</price>
    <vendor>Ager</vendor>
    <stock_quantity>2</stock_quantity><picture>https://x/ag771.jpg</picture>
    <param name="Колір"><value lang="uk">Бордовий</value></param>
  </offer>""" % р for р in ("S", "M", "L"))
        _xml = ПО._зібрати_xml().replace("</offers>", _без_ключа + "\n</offers>")
        open(шлях, "w", encoding="utf-8").write(_xml)
        import colorspace as _cs
        offers, _діаг = feed.читати_yml(шлях)
        каталог = []
        for o in offers:
            h = ПО._HEX.get(o.get("group_id"))
            if not h:
                continue
            каталог.append(dict(id=o["id"], group_id=o["group_id"], lab=_cs.hx(h),
                                впевненість=0.8, колір_назва=o["колір_назва"],
                                фото_ключ=(o["фото"] or [None])[0]))
        feed.лексикон(каталог, мін_n=2)
    except Exception as _e:
        import os as _os, traceback as _tb   # п.14: не мовчати (форма bridge)
