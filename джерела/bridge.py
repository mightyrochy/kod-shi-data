        с2["година"] = int((int(с2["година"]) + зсув) % 24); опис.append("година %+d (%+.0f %% доби)" % (зсув, частка * 100))
        т2, n = _re_сц.subn(r"\b(\d{1,2}):(\d{2})\b", "%02d:\\2" % с2["година"], т2, count=1)
        if not n: опис.append("у тексті випадку години нема — не підмінено")
