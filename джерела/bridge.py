_РЕГ_ІД_ПРАВИЛА = _re.compile(r"\s*[·,;]?\s*\b[KRКР]-[A-ZА-Я]{2,6}-\d{2}\b\s*\+?\s*")


def _без_ід_рядків(текст):
    """Те саме, що `_без_ід`, але ПО РЯДКАХ: промпти рук багаторядкові, і
    згортання пробілів зʼїло б переводи рядків, на яких стоїть формат
    «ПІДПИС: / ОБРАЗ: / СВІДОМО:». (02.09.2026: у руці 1 їхали K-COMP-02,
    K-PC-05, R-PC-01 — із полюсів образу й застережень схем; гейт на ID
    стояв лише на пораді.)"""
    return "\n".join(_без_ід(р) if _РЕГ_ІД_ПРАВИЛА.search(р) else р
                     for р in str(текст or "").split("\n"))


def _без_ід(текст):
    """ID правил вирізаються з тексту ДО моделі, а не забороняються їй словами.

    Преамбула каже «не називай кодів правил», але це вимога до слухняності, а код
    може просто не дати чого називати. `outfit.сценарій` пише ноти виду
    «вечір +0.0 — … (K-KOH-06 + Emily Post, T3)»: без цього коди їхали б у промпт
    і випливли б у відповіді жінці першим же переказом ноти. Провенанс (T3, автор)
    лишається — він осмислений для людини; зникає лише внутрішній ідентифікатор."""
    ч = _РЕГ_ІД_ПРАВИЛА.sub(" ", str(текст))
    ч = _re.sub(r"\(\s*[,;+]\s*", "(", ч)
    ч = _re.sub(r"\(\s*\)", "", ч)
    return _re.sub(r"\s{2,}", " ", ч).strip()


