        # мітки для чіпів судді — з руки B (вона визначає, ЩО взагалі перевіряємо)
        # ГРУПА ЇДЕ РАЗОМ ІЗ ЯРЛИКОМ: із силуетним блоком чіпів судді стало 28
        # замість 20, і на телефоні це стіна однакових кнопок.
        правила=[dict(код=p["код"], ярлик=p["ярлик"], група=p.get("група", "ремесло")) for p in бB["правила"]],
