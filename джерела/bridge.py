def _шкіра(d):
    """Шкіра приходить одним hex АБО списком точок (щока, лоб, щелепа).

    ЧОМУ СПИСОК, І ЧОМУ НЕ ТАК, ЯК ВОЛОССЯ. Це РІЗНІ речі, і плутати їх не можна.
    Кілька тонів волосся — ВЛАСТИВІСТЬ людини: мелірування справді несе крок
    світлоти, і цей крок іде в правило. Кілька точок шкіри — не властивість, а
    ПОВТОРНИЙ ЗАМІР однієї величини: обличчя не дає образу «крок світлоти
    задарма». Тому розкид шкіри НІКОЛИ не потрапляє в бриф — він говорить лише
    про якість виміру.

    НАВІЩО ВЗАГАЛІ. Заміряно на трьох профілях: одна точка на щоці несе ±8–14 L*
    похибки від тіні, відблиску й тонального, і на двох профілях із трьох ця
    похибка ПЕРЕКИДАЄ рівень контрасту (середній↔високий, низький↔середній), а
    рівень задає крок світлоти в брифі: 25 проти 45 проти 100 одиниць. Медіана
    трьох точок збила похибку з 8.9 до 1.0 L*.

    Медіана, а не середнє: одна точка в тіні — це викид, і середнє його тягне."""
    ш = d.get("шкіра")
    сп = [ш] if isinstance(ш, str) else [x for x in (ш or []) if x]
    return сп[:6]


def _медіана_lab(labs):
    import statistics as _st
    return tuple(_st.median([l[i] for l in labs]) for i in range(3))


def _волосся(d):
    """Волосся приходить СПИСКОМ довільної довжини. Один hex — законний випадок
    (рівний однотонний колір), а не помилка. Кілька — теж законний: мелірування,
    балаяж, відрослі корені й сивина дають кілька кроків світлоти на голові, і
    outfit.контраст_особи це вміє (збирає всі риси з ключем на «волосся», рахує
    σ і, коли σ > step_min, каже: крок в образі вже є)."""
    в = d.get("волосся")
    сп = [в] if isinstance(в, str) else [x for x in (в or []) if x]
    return сп[:МАКС_ТОНІВ] or [d["шкіра"]]


def _зсув_волосся(labs, ціль_L):
    """Ручка світлоти рухає ВСІ пасма на ту саму дельту: інакше виправлення
    середньої світлоти знищило б розкид, тобто ту саму річ, заради якої
    пасма й питаються."""
    if ціль_L is None or not labs:
        return labs
    д = float(ціль_L) - labs[0][0]
    return [(max(3.0, min(97.0, L + д)), a, b) for L, a, b in labs]


def _features(d):
    точки = [cs.hx(x) for x in _шкіра(d)]
    ш = _медіана_lab(точки); о = cs.hx(d["очі"])
    вл = _зсув_волосся([cs.hx(x) for x in _волосся(d)], d.get("L_волосся"))
    if d.get("L_шкіра") is not None:
        ш = (float(d["L_шкіра"]), ш[1], ш[2])
    F = cs.features(ш, вл[0], о)
    for i, lab in enumerate(вл[1:], start=2):
        F = cs.перерахувати_рису(F, "волосся_%d" % i, lab, kind="волосся")
    # K-ECHO-01 / Zyla (24.08.2026): темне кільце райдужки зі стенда — окрема риса
    # «очі_кільце» (кандидат «її чорний»); «очі» лишається тілом райдужки.
    if d.get("очі_кільце"):
        try: F = cs.перерахувати_рису(F, "очі_кільце", cs.hx(d["очі_кільце"]), kind="очі")
        except Exception: pass
    return F, ш, вл, о, точки


def _збірка(d, донорський=False):
    """dict із JS → (F, T, зріст, сценарій-kwargs)."""
    F0, ш, вл, о, _ = _features(d)
    в = вл[0]
    зріст = float(d["зріст"])
    об = {k: float(v) for k, v in d["обхвати"].items() if v not in (None, "")}
    if донорський:
        ш, в, о, об = Б.донор(ш, в, о, зріст, об)
