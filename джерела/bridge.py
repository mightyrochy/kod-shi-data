    # «палітра» вимагає розвилки хоча б на дві схеми; якщо її нема — поломка не
    # в наборі, і це кажеться назовні, а не мовчки пропускається.
    # ЖЕРЕБ, ДОНОР, ЗЛАМАНА ПАЛІТРА Й СЦЕНАРІЙ — В ОДНОМУ МІСЦІ (`_рука2`),
    # звідки їх бере і `від_моделі`: інакше рука 2 судилась не тим, чим складала.
    поломки, Fд, Tд, пд, гд, сц2, текст2, псування, _дост = _рука2(d, гілка, F, T, п, зріст, kw, якір, намір)
    _інв = "ремесло" in поломки
    бC = Б.бриф(пд, Tд, гд, інвертувати=_інв, вимкнені=вимк, вимоги=вимоги)
    # метал донора рахується з його ж рис і випадково збігався з металом B —
    # інверсія «навпаки від донора» поверталась у вихідне значення. Тому
    # перекидаємо відносно РУКИ B, а не відносно донора.
