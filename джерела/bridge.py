# ── КОЛІР ЛЮДИНИ: перевірка словами, а не оком ──────────────────────
# ЧОМУ ЦЕ Є. Піпетка по фото давала систематично хибні числа: волосся блондинки
# зчиталось як L*39 («темне») замість L*72, і бриф перевернувся — 7 рядків з 10
# інші. Вбудований extraction_sanity цього НЕ ловить (ΔE00 між хибним волоссям і
# очима лишився > 8). Отже ловити мусить людина — але вона не може звірити hex.
# Може звірити СЛОВО: «волосся темне» блондинка спростує з першого погляду.
_МЕЖІ_L = (22, 38, 55, 72, 101)
_СЛОВА = dict(
    шкіра=("дуже темна", "темна", "середня", "світла", "дуже світла"),
    волосся=("дуже темне", "темне", "середнє", "світле", "дуже світле"),
    очі=("дуже темні", "темні", "середні", "світлі", "дуже світлі"))


def _слово(L, риса):
    i = next(i for i, межа in enumerate(_МЕЖІ_L) if L < межа)
    return _СЛОВА[риса][i]


def _перефарбувати(hex_, L=None):
    lab = cs.hx(hex_)
    if L is not None:
        lab = (float(L), lab[1], lab[2])
    r, g, b = cs.to_rgb(*lab)
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v * 255))) for v in (r, g, b))


def кольори(вхід):
    """Що код зрозумів із поданих кольорів — словами. Плюс ручка світлоти на тій
    осі, на якій стоїть увесь контраст."""
    СЛ.почати()                      # один виклик моста = один слід
    d = _json.loads(вхід) if isinstance(вхід, str) else вхід
    F, ш, вл, о, точки = _features(d)
    import outfit as O
    к = O.контраст_особи(F, "uncontrolled")
    риси = dict(
        шкіра=dict(hex=_hex_lab(ш), L=round(cs.lch(ш)[0], 1), слово=_слово(cs.lch(ш)[0], "шкіра")),
        очі=dict(hex=_hex_lab(о), L=round(cs.lch(о)[0], 1), слово=_слово(cs.lch(о)[0], "очі")),
        волосся=[dict(hex=_hex_lab(l), L=round(cs.lch(l)[0], 1),
                      слово=_слово(cs.lch(l)[0], "волосся")) for l in вл])
    Ls = [x["L"] for x in риси["волосся"]]
    if len(Ls) > 1 and max(Ls) - min(Ls) >= 4:
        _род = {"дуже темне": "дуже темного", "темне": "темного", "середнє": "середнього",
                "світле": "світлого", "дуже світле": "дуже світлого"}
        вол = (f"волосся від {_род[_слово(min(Ls), 'волосся')]} до {_род[_слово(max(Ls), 'волосся')]} "
               f"({min(Ls)}–{max(Ls)} зі 100, розкид {к.get('внутрішній_розкид_волосся')})")
    else:
        вол = f"волосся {_слово(к.get('L_волосся'), 'волосся')} ({к.get('L_волосся')} зі 100)"
    речення = (f"шкіра {риси['шкіра']['слово']} ({риси['шкіра']['L']} зі 100), "
               f"{вол} → контраст {к.get('рівень')}")
    # ЧИ ВИСТАЧАЄ ЗАМІРІВ ШКІРИ — без вигаданого порога. Замість «розкид > N»
    # питаємо про НАСЛІДОК: чи дає найтемніша точка інший РІВЕНЬ контрасту, ніж
    # найсвітліша. Якщо так — від вибору точки залежить крок світлоти в брифі
    # (25 / 45 / 100 одиниць), і одна точка тут не годиться. Якщо ні — розкид є,
    # але він нічого не вирішує, і чіплятись до людини нема за що.
    хитко, розкид_ш = False, 0.0
    if len(точки) > 1:
        Lт = [p[0] for p in точки]
        розкид_ш = round(max(Lт) - min(Lт), 1)
        краї = []
        for p in (min(точки, key=lambda x: x[0]), max(точки, key=lambda x: x[0])):
            Fк = cs.features(p, вл[0], о)
            for i, lab in enumerate(вл[1:], start=2):
                Fк = cs.перерахувати_рису(Fк, "волосся_%d" % i, lab, kind="волосся")
            краї.append(O.контраст_особи(Fк, "uncontrolled").get("рівень"))
        хитко = краї[0] != краї[1]
    згода = _згода_зчитувань_шкіри(точки)
    return _json.dumps(dict(
        риси=риси, контраст=dict(рівень=к.get("рівень"), щілина=к.get("value_gap"),
                                 розкид=к.get("внутрішній_розкид_волосся")),
        тонів=len(вл), точок_шкіри=len(точки), розкид_шкіри=розкид_ш,
        шкіра_хитка=хитко, згода_зчитувань=згода,
        # СЛІД ВІДДАЄ ЛИШЕ ЦЕЙ ЕНДПОЙНТ І ЩЕ ДВА. Доти `кольори` слід НЕ віддавав,
        # і це не косметика: R-PC-09 спрацьовує саме тут (зчитувань шкіри більше
        # ніде не буває кілька), писав запис у глобальний акумулятор і той запис
        # ніхто не читав. Тобто правило виконувалось, а гейт досяжності законно
        # звітував його мертвим — вихід його не ніс.
        слід_правил=СЛ.зібрати(),
        речення=речення, примітка=к.get("примітка"),
        підозри=[p["діагноз"] for p in cs.extraction_sanity(F)["підозри"]]),
        ensure_ascii=False)


def _згода_зчитувань_шкіри(точки):
    """R-PC-09. Чи два зчитування обличчя — це та сама шкіра, з допуском, що
    масштабується світлотою.

    ЧОМУ ЦЕ ТУТ, А НЕ В `colorspace`. Правило вже було написане повністю —
    `допуск_шкіри`, `та_сама_шкіра`, джерело (Paravina та ін.), провенанс,
    неперервний множник, названа межа. І його не викликав ЖОДЕН модуль: `grep`
    по всьому дереву давав нуль споживачів поза самим `colorspace.py`. Тобто це
    другий випадок тієї самої хвороби, що й `coordination.py`: правило написане,
    відрегресоване й мертве, бо між ним і живим шляхом нема жодного рядка.

    ЖИВА ТОЧКА РІШЕННЯ ЗНАЙШЛАСЬ ТУТ. `_features` бере СПИСОК зчитувань шкіри й
    згортає їх у `_медіана_lab` — тобто система вже ухвалює рішення «це одна
    шкіра, її можна усереднити», і ухвалює його МОВЧКИ, без жодного допуску.

    ЩО ЦЕ МІНЯЄ В РІШЕННІ (before/after):
      before — два зчитування зводяться в медіану незалежно від того, наскільки
               вони розійшлись. Поруч є `розкид_шкіри` (max−min по L*), але це
               ЛИШЕ СВІТЛОТА й лише число без порога: воно не каже, чи медіана
               законна. Якби поріг додали скаляром, він систематично частіше
               таврував би темну шкіру — рівно та нерівність, яку правило знімає.
      after  — розходження міряється повним ΔE00 і порівнюється з допуском, що
               росте зі спаданням L* (×1.0 на L*66 → ×1.6 на L*35). Коли згоди
               нема, це сказано: палітра нижче стоїть на усередненні двох різних
               вимірів, і людина це бачить.

    ЧИЙ ЦЕ БІК: КОД. Це вимір і поріг, модель тут не має що додати.
    ДЕ ЛАМАЄТЬСЯ: множник — підлога, не повне виправлення (похибка видобування на
    темній шкірі теж росте, і наскільки — не виміряно). Правило нічого не каже,
    коли зчитування одне: одна точка не має з чим не погодитись.
    """
    if len(точки) < 2:
        return dict(перевірено=False,
                    чому="одне зчитування шкіри — згоди нема з чим міряти")
    L = [p[0] for p in точки]
    a = min(точки, key=lambda x: x[0])
    b = max(точки, key=lambda x: x[0])
    р = cs.та_сама_шкіра(a, b, L_шкіри=sum(L) / len(L))
    try:
        СЛ.запис("R-PC-09", "згода зчитувань шкіри", "міст",
                 значення="ΔE00 %.2f проти допуску %.2f (×%.2f)"
                          % (р["dE00"], р["допуск"], р["множник"]),
                 напрям=("згода" if р["same"] else "розходяться"))
    except Exception:
        pass
    return dict(перевірено=True, згода=bool(р["same"]), dE00=р["dE00"],
                допуск=р["допуск"], множник=р["множник"],
                чому=р["чому"],
                наслідок=(None if р["same"] else
                          "зчитування розходяться понад допуск — усе нижче стоїть "
                          "на медіані двох різних вимірів, а не на одному кольорі"))


def _hex_lab(lab):
    r, g, b = cs.to_rgb(*lab)
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v * 255))) for v in (r, g, b))


def чипи(вхід=None):
    """Запасний шлях без фото: сходинки, з яких людина обирає себе. Хеси
    рахуються тут, а не вписані рукою, щоб сидіти в тому самому просторі, у
    якому код потім міряє."""
    ш = [_перефарбувати(_hex_lch(L, 26, 52)) for L in (34, 44, 54, 63, 71, 78, 84)]
    в = [_перефарбувати(_hex_lch(L, c, h)) for L, c, h in
         ((12, 4, 60), (24, 14, 55), (36, 20, 58), (48, 24, 62), (60, 26, 70),
          (72, 26, 78), (82, 18, 82), (40, 40, 32))]
    о = ["#3b2c22", "#5d4632", "#7d6a4f", "#6f7f6a", "#5b7f86", "#7c98b5", "#9aa7ad", "#4a5b46"]
    return _json.dumps(dict(шкіра=ш, волосся=в, очі=о), ensure_ascii=False)


def _hex_lch(L, C, h):
    import math
    c = min(C, cs.c_max(L, h))
    a, b = c * math.cos(math.radians(h)), c * math.sin(math.radians(h))
    r, g, bl = cs.to_rgb(L, a, b)
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v * 255))) for v in (r, g, bl))
