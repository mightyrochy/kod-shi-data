    # промахувалися б повз бюджет у будь-який бік.
    # РЕЗУЛЬТАТ КОМПОЗИТОРА РАХУЄТЬСЯ РАЗ. Перша версія цього пошуку не передавала
    # `рез`, і кожна з ~11 ітерацій піднімала `composer.зібрати` наново: на повному
    # каталозі з усіма слотами прогін мовчки вбивало по пам'яті, без трейсбека.
    низ_, верх_ = 1, sum(len(v) for v in (пак.get("кандидати") or {}).values())
