            A=[], В=[], Г=[],
            # ID КОРПУСУ СТОЇТЬ ПОРУЧ ІЗ ЯРЛИКОМ, А НЕ ЗАМІСТЬ НЬОГО.
            # Ярлик — те, що людина здатна сказати перед дзеркалом («довжини
