def нормувати_елісітацію(вх):
    """Одна відповідь людини → два словники, які чекають РІЗНІ споживачі.

    СПІЙМАНО 29.08.2026 прогоном, не контрактом. `palette.тепло_з_елісітації`
    чекає білий як «вершковий/оптичний», а `palettes._hue` — той самий білий як
    «теплий/холодний». Обидва мовчать на чужому слові: перший не додає каналу,
    другий тихо рахує нуль. Жоден аудит контрактів цього не бачить, бо контракт
    не порушено. Тому переклад живе в ОДНОМУ місці — тут, на межі.
    """
    в = dict(вх or {})
    драп = {k: в[k] for k in ("білий", "метал", "нейтралі") if в.get(k)}
    # СЛОВНИК ДРАПІРОВКИ → СЛОВНИК РАНГУ (05.09.2026, спіймано прогоном: три різні
    # драпіровки давали побайтово однакові «рекомендовані»). bases._температура_людини
    # чекає метал ∈ {золото, срібло}, нейтраль ∈ {теплі, холодні}, білий ∈ {теплий,
    # холодний}; показ віддає метал «теплі/холодні», білий «золото/срібло», а
    # `нейтралі` в показі — про хрому (приглушені/яскраві), не про температуру.
    # Доти всі три голоси були None, і палітра рахувалась із фото (надійність 0.15).
    _МЕТАЛ = {"теплі": "золото", "теплий": "золото", "золото": "золото",
              "холодні": "срібло", "холодний": "срібло", "срібло": "срібло"}
    _БІЛИЙ = {"золото": "теплий", "теплий": "теплий", "вершковий": "теплий",
              "срібло": "холодний", "холодний": "холодний", "оптичний": "холодний"}
    if в.get("метал") in _МЕТАЛ:  в = dict(в, метал=_МЕТАЛ[в["метал"]])
    if в.get("білий") in _БІЛИЙ:  в = dict(в, білий=_БІЛИЙ[в["білий"]])
    сам = {}
    if в.get("метал"):  сам["метал"] = в["метал"]
    if в.get("білий"):  сам["білий"] = _БІЛИЙ_У_САМОЗВІТ.get(в["білий"], в["білий"])
    if в.get("барви"):  сам["барви"] = в["барви"]
    # хрома: «нейтралі приглушені/яскраві» — це і є самозвіт про власні барви для
    # bases.ЦІЛЬ_ХРОМИ (6 / 22); без нього ціль стояла на 12 і всі кольорові основи
    # вилітали в «не радимо»
    if в.get("нейтралі") in ("приглушені", "яскраві") and not сам.get("барви_хрома"):
        сам["барви_хрома"] = в["нейтралі"]
    return dict(драп=драп, самозвіт=сам)


def _самозвіт(d, донорський=False):
    """Те, що людина сказала про себе, а не те, що видно на фото.

    Вісь colour contrast (K-CLR-01 §2) рахується з барвності волосся й ОЧЕЙ, але
    з телефонного фото не стверджується: надійність хроми 0.35 при порозі 0.5.
    Канон (K-PC-01) прямо приписує в цьому місці питати людину, а не вимірювати.
    Донор перекидає відповіді — це властивість особи, отже плацебо її вивертає."""
    с = dict(d.get("самозвіт") or {})
    if донорський:
        if с.get("барви"):
            с["барви"] = _ІНШІ_БАРВИ.get(с["барви"], с["барви"])
        if с.get("метал"):
            с["метал"] = {"золото": "срібло", "срібло": "золото"}.get(с["метал"], с["метал"])
    return с


