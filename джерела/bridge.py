АХРОМАТИЧНА_МЕЖА = 12.0     # K-COL-06: C* < 12 — ахроматична сім'я, тону нема


def тони(вхід=None):
    """Ряд якорів тону на вибір, і першим — ТОН ОЧЕЙ, коли він узагалі є.

    ЧОМУ ОЧІ ТУТ ЛЕГІТИМНІ, ХОЧА K-PC-05 ЇХ ГЕЙТИТЬ. Гейт забороняє СТВЕРДЖУВАТИ,
    що якийсь тон людині личить: це претензія на вимір, а надійність hue з
    телефонного фото 0.35. Але якір — не твердження, а ВИБІР: решта цього ряду
    (цегляний, синій, винний) не має під собою взагалі жодного виміру, і ми її
    спокійно пропонуємо. Тон очей як опція епістемічно не гірший — він принаймні
    походить від людини. Схема далі будує від нього ті самі Δh, що й від будь-якого
    іншого якоря; правилом лишається саме Δh, а не «вам личить блакитний».

    З ОЧЕЙ БЕРЕТЬСЯ ТІЛЬКИ ТОН. Світлота й барвність райдужки в якір не йдуть:
    вікна L*/C* задають слоти, а очі — мала площа з низькою хромою, і тягнути її
    числа в одяг означало б одягти людину в колір очного яблука.

    КОЛИ ТОНУ НЕМА. Сірі, майже чорні й темно-карі очі дають C* нижче за 12 —
    за K-COL-06 це ахроматична сім'я. Тон там не існує, а не «слабкий»: кут h
    рахується з майже нульового вектора й буде шумом. У такому разі опція не
    пропонується взагалі, і чому — сказано словами."""
    d = _json.loads(вхід) if isinstance(вхід, str) else (вхід or {})
    імена = [(20, "цегляний"), (55, "теплий пісок"), (85, "оливковий"),
             (130, "зелений"), (170, "смарагдовий"), (200, "морський"),
             (250, "синій"), (290, "фіолетовий"), (330, "винний"), (355, "червоний")]
    ряд = [dict(h=h, назва=н, зразок=Б._hex(52, 30, h), з_очей=False) for h, н in імена]
    очі = d.get("очі")
    примітка = None
    if очі:
        L, C, h = cs.lch(cs.hx(очі))
        if C >= АХРОМАТИЧНА_МЕЖА:
            ряд.insert(0, dict(h=round(h, 1), назва="тон ваших очей",
                               зразок=Б._hex(52, 30, h), з_очей=True))
        else:
            # ФОРМУЛЮВАННЯ БУЛО НЕПРАВДИВЕ Й ОБРАЗЛИВЕ. «Майже нема кольору»
            # читається як «ваші очі безбарвні» — а сіро-зелене око має тон,
            # просто мало хроми. Виміряно на реальному фото: кільце райдужки
            # (5.4 тис. пікселів, без зіниці й відблисків) дає C* ≈ 8–9, і три
            # незалежні заміри того самого ока розійшлись у ТОНІ на 100°:
            # 72° (моє), 121° (ChatGPT #777B6D), 172° (Gemini #759087).
            # Саме цей розкид і є доказом: ненадійна не барвність, а НАПРЯМОК.
            # При C* ≈ 8 кут h рахується з майже нульового вектора, і кожен
            # семплер дістає свій. Тому опція не пропонується — але сказати
            # треба саме це, а не «кольору нема».
            примітка = ("Хрома ваших очей низька (C* %.0f при порозі 12 за K-COL-06). "
                        "Колір у них є, але при такій хромі НАПРЯМОК тону з фото "
                        "ненадійний: різні заміри того самого ока розходяться на "
                        "десятки градусів. Тому код не пропонує «тон ваших очей» — "
                        "оберіть тон акценту нижче самі, і схеми розійдуться." % C)
    return _json.dumps(dict(ряд=ряд, примітка=примітка), ensure_ascii=False)


