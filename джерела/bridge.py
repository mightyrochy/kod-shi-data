def _стислі_знахідки(зн, скільки=8):
    """Знахідки у вигляді, придатному для НАСТУПНОЇ ІТЕРАЦІЇ моделі: суть, сила
    словами й речі, яких вона стосується. Сила лишається — це матеріал ремонту,
    без неї «зауваження» не відрізнити від «дрібниці». Числа не подаються як
    оцінка образу (R-ABC-08): вони описують окреме ребро, не образ."""
    вих = []
    for z in (зн or []):
        if len(вих) >= скільки:
            break
        if _питання_або_нуль(z):
            continue
        вих.append(dict(правило=z.get("правило"), сила=z.get("сила"),
                        сила_нп=z.get("сила_нп"), суть=z.get("суть"),
                        речі=z.get("речі"),
                        **({"свідомий": z["свідомий"]} if z.get("свідомий") else {})))
    return вих


def _питання_або_нуль(z):
    """Знахідка без виміру: регістр «питання» (дефолтний крій, невідома довжина,
    не виміряний баланс) або сила 0/None. Це запити на дані, не зауваження."""
    if z.get("сила") == "питання" or z.get("регістр") == "питання":
        return True
    # «тут не вирішує нічого / нема що сказати» — це відсутність знахідки, не знахідка
    # (K-SHO-07 давав такий рядок на 85 % образів у чотирьох сценаріях, 05.09)
    if _re.search(r"не вирішує нічого|нема що сказати|не впливає тут|нічого не змінює", str(z.get("суть") or ""), _re.I):
        return True
    нп = z.get("сила_нп")
    try:
        return нп is None or float(нп) <= 0.0
    except (TypeError, ValueError):
        return True


