def виклик(ім, вхід):
    """Один вхід із JS: імена функцій кирилицею через проксі бувають крихкі
    між версіями Pyodide, тому диспетчер тут, а не там."""
    # ЧОТИРИ ЕНДПОЙНТИ ЗНЕСЕНО (Н-02-03): `тони`, `кольори`,
    # `пояснення`, `приміряння`. Жоден не мав викликача — ні в `показ.html`, ні в
    # `build_артефакт`, ні в `worker*.js`.
    # П'ЯТИЙ — `порада` (П-5). Читача не мав узагалі:
    # `показ.html` його не кличе (0 збігів `виклик('порада'`), гейт 3 `build_артефакт`
    # вимагав у збірці рядок `міст("порада"`, якого в `показ.html` теж нема, а сам гейт
    # лежить на шляху `зібрати`, який читає `шаблон_артефакта.html` — файл, якого в
    # репозиторії НЕМА. Єдиний живий виклик стояв у смоук-тесті режиму «лайт»; CI
    # збирає режимом «показ-повний», тож він не виконувався — і `порада` падала
    # NameError'ом на `кольори(d)` (ендпойнт `кольори` знесено 13.09, функції в
    # `bridge` не лишилось). Тобто ендпойнт був мертвий і зламаний одночасно.
    # Разом із ним знято `brief.ПОРАДА_ПРЕАМБУЛА` (єдиний читач) — це був ще й
    # промпт УКРАЇНСЬКОЮ прозою коду (аудит/ПРОДУКТ.md п.12), зібраний повз `збирач_промптів`.
    # Єдиною згадкою лишалась батарея `gate_reach`, яка кликала їх, щоб підняти
    # покриття, — тобто прилад ходив туди, куди продукт не ходить ніколи.
    # Решта восьми тримається реальним читачем: `палітри`/`запити`/`від_моделі`/
    # `опис`/`показ`/`паспорт` — шість викликів живого шляху; `вердикт` —
    # `показ.html:1618,1643` (Н-P12); `довідник` — `показ.html:2403` (Т-08);
    # `чипи` — JS, який пише `build_артефакт.py`.
    # `помади` — сходинка відтінків помади й поділ за
    # R-MUA-03. Читач — `показ.html` (редактор «Макіяж сьогодні»): доти колір губ
    # брався нативним вибором браузера, тобто ЄДИНЕ поле паспорта, де кольори не
    # приходили з коду. Тепер приходять звідси, і другої таблиці кольорів у JS нема.
    # `річ_з_фото` — вимір кольору речі з фото
    # пікселями й вердикт коду «чи підійде». Читач — `показ.html` (`оцінитиРечіЗФотоП`)
    # після виклику 0, у якому стилістка назвала річ і рамку.
    # `мова` — мовний шар. Читач — `показ.html`
    # (`мовоюП`): кожен текст для жінки (чат, картка, підпис приміряння) іде крізь модель
    # шару, а цей ендпойнт дає їй промпт і читає її відповідь.
    # `оцінка` — «Оціни мій образ». Читач — `показ.html`
    # (`оцінитиОбразП`, окремий екран): речі з фото моделлю із зором, суд образу цілим, перевірені
    # зміни й відповідь на її питання поверх суду (`міст_оцінка`, `оцінка_образу`).
    # `стилістка` — її питання про образ іде не
    # довідці про застосунок, а функціональній моделі з її речами, вердиктом коду й фото.
    # Читач — `показ.html` (`стилісткаП`).
    # `приміряння` (П-1) — промпт картинки «вона в цьому образі». Те саме
    # ім'я знесеного (Н-02-03), але з читачем: `показ.html` (`приміряти`).
    # `колір` (Е2-межі-показу): відповідь моделі про її кольори з портрета читає реєстр (форма PORTRAIT_COLOURS,
    # `міст_вхід.прийняти_колір`), а не показ. Читач — `показ.html` (`застосуватиКольори`).
    # `помічниця` (П-4): її питання про застосунок — промпт зі збирача англійською
    # (`міст_помічниця`). Читач — `показ.html` (`помічникП`).
    return {"палітри": палітри, "запити": запити, "від_моделі": від_моделі,
            "приміряння": приміряння,
            "чипи": чипи, "довідник": довідник, "паспорт": паспорт,
            "вердикт": вердикт, "показ": показ, "опис": опис,
            "помади": помади, "річ_з_фото": річ_з_фото, "мова": мова,
            "оцінка": оцінка, "стилістка": стилістка, "помічниця": помічниця,
            "вибір_палітри": вибір_палітри, "колір": колір}[ім](вхід)


async def виклик_а(ім, вхід):
    """`виклик` для кроку, що не мусить займати головний потік сторінки на секунди: «суд» оцінки йде з
    поступками (`міст_оцінка.оцінка_а`), решта — як `виклик`."""
    if ім == "оцінка":
        return await оцінка_а(вхід)
    return виклик(ім, вхід)
