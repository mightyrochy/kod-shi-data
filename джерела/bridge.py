def порада(вхід):
    """Пакет контексту для вільної розмови жінки з моделлю на екрані випадку.

    ЩО ЦЕ МІНЯЄ НАД РЕАЛЬНОЮ РІЧЧЮ (before/after). Before: жінка, чиєї нагоди нема
    в списку, або ставить навмання, або пише вільними словами й тисне «розібрати» —
    а якщо ші не зіставило слова з таблицею, вона дізнається про це аж на екрані
    образів, після хвилин збирання. Спитати «а 19:00 у кафе — це ошатно чи ні?» нема
    де. After: питання ставиться тут, до збирання, і відповідь спирається на числа,
    з якими код ПІСЛЯ цього працюватиме.

    ЧОМУ ПАКЕТ БУДУЄТЬСЯ ТУТ, А НЕ В JS. Екран показує ТАБЛИЧНИЙ діапазон нагоди
    («цільова формальність 3–6»), а `формальність.сценарій` додає до нього вечірній підйом,
    зсув господаря й погодний шар — і судить образ уже підсумковим. Пакет, зібраний
    у JS із того, що видно на екрані, розійшовся б із тим, чим судять: рівно клас
    «імена полів збігаються, словник значень розходиться», який проєкт уже ловив.
    Тому поля беруться тим самим `_ПОЛЯ_СЦЕНАРІЮ`, що йде в композитор, і число
    рахує та сама функція.

    ЦІНА НАВМИСНО НИЗЬКА: ні фіду, ні композитора. Це інтерактивна розмова, а прогін
    кольорів стенд-фіду коштує секунд. Наслідок чесно заявлений у преамбулі: речей
    каталогу модель не бачить і називати їх не має права."""
    СЛ.почати()
    d = _json.loads(вхід) if isinstance(вхід, str) else вхід
    import outfit as _O
    import реєстр_правил as _РЕЄСТР, формальність as _ФОРМ   # Н-02-01, сесія 4
    сц = d.get("сценарій") or {}
    поля = {k: сц[k] for k in _ПОЛЯ_СЦЕНАРІЮ if сц.get(k) not in (None, "")}
    с = _ФОРМ.сценарій(місце=поля.get("місце"), код=_ФОРМ.код_дрес(поля.get("дрес_код")),
                       година=поля.get("година"), нагода=поля.get("нагода"),
                       темп_c=поля.get("темп_c"), господар=bool(поля.get("господар")))
    lo, hi = с["діапазон"]

    # кольори словами — той самий шлях, що й на екрані профілю: жінка вже бачила
    # це речення там і може спростувати оком, якщо модель почне радити проти нього
    к = _json.loads(кольори(d))
    рядки = ["ЩО КОД ЗНАЄ ПРО ЦЮ ЖІНКУ", "· " + к["речення"]]
    if d.get("зріст"):
        рядки.append("· зріст %.0f см" % float(d["зріст"]))
    об = {k: v for k, v in (d.get("обхвати") or {}).items() if v not in (None, "")}
    if об:
        рядки.append("· обхвати: " + ", ".join("%s %.0f см" % (k, float(v)) for k, v in об.items()))
    намір = d.get("намір") or "conventional"
    рядки.append("· намір: " + {"conventional": "звичайно, без ризику",
                                "fashion_forward": "сміливо",
                                "statement": "statement — образ має заявляти"}.get(намір, намір))

    рядки += ["", "ВИПАДОК, ЯК ЙОГО ЧИТАЄ КОД",
              "· її словами: " + (d.get("випадок") or "—")]
    if поля.get("нагода"): рядки.append("· нагода з таблиці: %s" % поля["нагода"])
    if поля.get("місце"): рядки.append("· місце з таблиці: %s" % поля["місце"])
    if поля.get("дрес_код"):
        рядки.append("· рівень ошатності вона поставила РУКАМИ: %s" % поля["дрес_код"])
    рядки.append("· цільова формальність %.1f–%.1f зі шкали 1–10 (1 домашнє … 10 white tie). "
                 "Саме проти цього діапазону код судитиме образ." % (lo, hi))
    for н in (с.get("чому") or []):
        рядки.append("  — %s" % _без_ід(н))
    if с.get("вето"):
        рядки.append("· вето нагоди: " + _без_ід("; ".join(с["вето"])))
    if с.get("практика"):
        рядки.append("· практичні обмеження: " + "; ".join(с["практика"]))
    вл = с.get("weather_layer") or {}
    if вл.get("темп_c") is not None:
        см = вл.get("смуга") or {}
        рядки.append("· %s °C%s" % (вл["темп_c"],
                     (", за температурною мапою це %d шар(и): %s" % (см["шари"], _без_ід(см["нота"]))) if см else ""))
    if d.get("вимоги"):
        рядки.append("")
        рядки.append("ЇЇ ВЛАСНІ ВИМОГИ (вони мають старшинство над усім вище): " + d["вимоги"])

    # ── МЕЖІ КАЖУТЬСЯ МОДЕЛІ, А НЕ ЛИШЕ ЛЮДИНІ ───────────────────────────────
    # Інакше модель заповнює прогалину здогадом: на прогонах рук вона просила фото,
    # якого нема, і віддавала нуль образів (brief.ЗАВДАННЯ_БЕЗ_ФОТО, той самий клас).
    рядки += ["", "ЧОГО КОД НЕ ЗНАЄ І ЧОГО НЕ МАЄШ ТИ",
              "· фото цієї жінки ти не бачиш — кольори прийшли числами, не з обличчя;",
              "· каталогу в цьому виклику нема: жодної реальної речі ти назвати не можеш;",
              "· образ ще не зібрано — ти говориш ДО збирання;",
              "· форму заповнює вона сама: ти можеш порадити, що виправити, але не змінюєш нічого."]

    контекст = "\n".join(рядки)
    return _json.dumps(dict(
        преамбула=Б.ПОРАДА_ПРЕАМБУЛА, контекст=контекст,
        діапазон=[lo, hi],
        # рядок для людини: вона мусить бачити, що саме віддали моделі, — той самий
        # принцип, що зі свотчами кольору («спростувати можна оком, за секунду»)
        видно="Ші дали: %s; ціль %.1f–%.1f; %s"
              % (к["речення"], lo, hi,
                 ("ваші вимоги передані" if d.get("вимоги") else "вимог ви не писали")),
        слід_правил=СЛ.зібрати()), ensure_ascii=False)


