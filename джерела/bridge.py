def виклик(ім, вхід):
    """Один вхід для JS через Pyodide."""
    функція = _маршрут(ім)
    if функція is None:
        raise KeyError(ім)
    return функція(вхід)


async def виклик_а(ім, вхід):
    """Оцінка й пошук поступаються потоку між кроками, решта йде через `виклик`."""
    if ім == "оцінка":
        from міст_оцінка import оцінка_а
        return await оцінка_а(вхід)
    if ім == "пошук_речі":
        from пошук_речі import пошук_а
        return await пошук_а(вхід)
    return виклик(ім, вхід)
