def _застосувати_паспорт(d):
    """Паспорт випадку — єдине джерело випадку для коду, чотирьох рук, опису й журналу.
    Що не заповнене — з обраного сценарію (дефолти вже в pipeline.паспорт_з_json)."""
    п = d.get("паспорт")
    if not isinstance(п, dict):
        return d
    import pipeline as _PL
    # ── ПАСПОРТ ВІДДАЄ ВСЕ, ЩО НЕСЕ, А НЕ ТРИ ПОЛЯ (07.09.2026) ──────────────
    #   before — сюди перепИсувались рівно `година`, `темп_c`, `дрес_код`
    #            (+ошатність, формат). Решту паспорт розбирав і викидав. Найдорожча
    #            втрата — `тривалість_год`: виклик 0 просить модель дістати її з
    #            тексту людини, `outer.стан` рахує нею ціну стану «накинуто»
    #            (K-OUT-32), а між ними стояв цей перелік із трьох імен.
    #   after  — злиття за оголошеним записом нагоди: паспорт переважає сценарій
    #            (слова людини про цю подію — перші), незнайоме не зникає мовчки.
    сц, _незнайомі = СЦ.з_показу(d.get("сценарій"), п)
    if _незнайомі:
        # не помилка й не мовчання: показ має право слати своє, але шов зобов'язаний
        # сказати, чого він не знає, — інакше наступне поле згине так само тихо
        сц["_незнайомі_поля"] = _незнайомі
    if п.get("ошатність"): сц["ошатність"] = list(п["ошатність"])
    вимоги = []
    if п.get("бажання"): вимоги.append("Хоче: " + "; ".join(п["бажання"]))
    вето = [w for k in ("типи", "тканини", "принти", "кольори", "зони") for w in (п.get("вето") or {}).get(k, [])]
    if вето: вимоги.append("Не хоче: " + "; ".join(вето))
    if п.get("настрій"): вимоги.append("Настрій: " + ", ".join(п["настрій"]))
    if п.get("слова"): вимоги.append("Її слова: «%s»" % п["слова"])
    # ГОТОВИЙ ШАР ТЕМА-6 (був у коді з 08.2026, показ його не годував): слова «не хочу» →
    # `жорстке_ні` (profile.жорстке_ні_фільтр у composer._придатні — абсолютний фільтр по
    # крою, тканині, кольору, типу, зоні, довжині, назві); зони → `вето` (outfit: правила
    # відкритих зон читають {"зони": [...], "ноги_вище_см": N}).
    _зони_словник = ("декольте", "спина", "руки", "плечі", "ноги", "живіт")
    _вето_обʼєкт = dict(d.get("вето") or {})
    _зони = [z for z in ((п.get("вето") or {}).get("зони") or []) if str(z).strip().lower() in _зони_словник]
    if _зони: _вето_обʼєкт["зони"] = sorted(set((_вето_обʼєкт.get("зони") or []) + [z.strip().lower() for z in _зони]))
    if п.get("ноги_вище_см"): _вето_обʼєкт["ноги_вище_см"] = п["ноги_вище_см"]
    _жорстке = list(d.get("жорстке_ні") or []) + [w for k in ("типи", "тканини", "принти", "кольори")
                                                  for w in (п.get("вето") or {}).get(k, [])]
    return dict(d, сценарій=сц, вимоги="\n".join(вимоги) or (d.get("вимоги") or ""),
                намір=(п.get("намір") or d.get("намір") or "conventional"),
                випадок=_PL.паспорт_рядком(п) or d.get("випадок") or "",
                жорстке_ні=sorted(set(str(w).strip().lower() for w in _жорстке if str(w).strip())) or None,
                вето=(_вето_обʼєкт or None))


