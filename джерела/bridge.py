                с2["нагода"] = нова; с2["місце"] = None      # місце береться з нової нагоди
                опис.append("нагода %s → %s (ошатність %.1f → %.1f)" % (_н, нова, центр(_м), центр(_O.НАГОДА_У_МІСЦЕ[нова])))
                т2n, n = _re_сц.subn(r"\b%s\b" % _re_сц.escape(str(_н)), нова.replace("_", " "), т2, count=1)
                if n: т2 = т2n
