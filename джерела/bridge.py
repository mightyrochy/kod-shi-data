def _ґратка_основ():
    """Носибельний простір клітинками. Рахується раз: від людини не залежить."""
    if _ҐРАТКА_КЕШ:
        return _ҐРАТКА_КЕШ["основи"], _ҐРАТКА_КЕШ["порядок"]
    import palettes as _PS, colorspace as _CS
    осн, порядок = {}, []
    # ── хроматика: сім'я × дуга × смуга світлоти ──
    Llo, Lhi = _МЕЖІ_ПРОСТОРУ_L
    Ls = [Llo + (Lhi - Llo) * (i + 0.5) / _СМУГ_L for i in range(_СМУГ_L)]
    _L_МІН = {"рожева": 55.0, "жовта": 45.0}     # той самий T3, що в `palettes.кольори`
    for сім, в in _PS.СІМ_Ї.items():
        for дуга in (в["тепла"], в["холодна"]):
            if not дуга:
                continue
            h = (дуга[0] + ((дуга[1] - дуга[0]) % 360) / 2) % 360
            темп = "тепла" if 0 <= h < 180 else "холодна"
            for L in Ls:
                if L < _L_МІН.get(сім, 0.0):
                    continue
                стеля_пов, _ = _CS.c_max_поверхня(L, h)
                верх = min(_МЕЖІ_ПРОСТОРУ_C[1],
                           стеля_пов if стеля_пов else _МЕЖІ_ПРОСТОРУ_C[1],
                           2500.0 / max(L, 1e-6))
                if верх < _МЕЖІ_ПРОСТОРУ_C[0]:
                    continue                      # тканина цього кольору не дає — фізика, не смак
                for і_см, см in enumerate(_СМУГИ_ХРОМИ):
                    C = _МЕЖІ_ПРОСТОРУ_C[0] + (верх - _МЕЖІ_ПРОСТОРУ_C[0]) * (і_см + 1) / len(_СМУГИ_ХРОМИ)
                    lab = _PS._lab(L, C, h)
                    ім, _як = _PS._назва(lab)
                    ключ = "%s·%s·%d·%s" % (ім, темп, round(L), см)
                    if ключ in осн:
                        continue
                    осн[ключ] = (_PS._hex(lab), ім)
                    порядок.append(ключ)
    # ── нейтралі: лише світлота, тон не значить нічого (K-COL-06) ──
    for L in Ls:
        lab = (L, 0.0, 0.0)
        ім, _як = _PS._назва(lab)
        # Нейтраль є в КОЖНІЙ смузі хроми: вона не має тону, тож перемикач
        # смуги не повинен її ховати — інакше на «насичених» зникає чорний.
        for см in _СМУГИ_ХРОМИ:
            ключ = "%s·нейтраль·%d·%s" % (ім, round(L), см)
            if ключ not in осн:
                осн[ключ] = (_PS._hex(lab), ім)
                порядок.append(ключ)
    _ҐРАТКА_КЕШ["основи"], _ҐРАТКА_КЕШ["порядок"] = осн, порядок
    return осн, порядок


