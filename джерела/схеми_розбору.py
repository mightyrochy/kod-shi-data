# -*- coding: utf-8 -*-
"""схеми_розбору.py — форми відповіді моделі разом із розбором і сторожем: `схема_відповіді` + функції розбору.

ЧОМУ ОКРЕМИЙ МОДУЛЬ (наряд 3.3, К-4). Описи форм (`схема_відповіді.СХЕМИ_ВІДПОВІДІ`: назва, як відповідає
модель, схема протоколу) читає збирач промптів — він низько в графі імпортів. Розбір і сторож форм — функції
модулів, що стоять вище за нього: розбір відповідей, повнота образу, рука без коду, річ із фото, уважний
вибір, заміна речі, оцінка образу. Доти вони прив'язувались у `схема_відповіді` обгортками з лінивим
імпортом — і граф мав цикл через усі ці модулі. Тут — ті самі обгортки (перенесено дослівно) і ті самі
схеми з прив'язаним розбором і сторожем; шукає їх той самий `схема_відповіді.схема_за_назвою` /
`визначити_схему`, тож форма одна на промпт і на розбір. Читає міст (`міст_відповіді`).
"""
import dataclasses as _dc

import протокол as _ПР
import схема_відповіді as _СВ
from схема_відповіді import понад_просили


def _розбір_образи_v1(текст, кандидати=None, каталог=None, просили=None, d=None):
    """Розбір образів із тексту відповіді; понад стелю `просили` — за «chosen» (`понад_просили`)."""
    import pipeline as _PL
    _розбір_відп = _PL.образи_з_тексту(текст, кандидати=кандидати, каталог=каталог)
    if _розбір_відп and isinstance(просили, int) and просили > 0 \
            and sum(1 for р in _розбір_відп if р.get("ід")) > просили:
        _обрано = (_ПР.розбір_за_схемою(текст, "ОБРАЗИ_V1")[0] or {}).get("обрано")
        _розбір_відп, _слід = понад_просили(_розбір_відп, _обрано, просили)
        if d is not None:
            d["_понад_просили"] = _слід
    return _розбір_відп


def _розбір_вибір_v1(текст, вибір_над=None, кандидати=None, каталог=None):
    """Розбір вибору з JSON."""
    import pipeline as _PL
    return _PL.вибір_з_json(текст, вибір_над or {}, кандидати=кандидати, каталог=каталог)


def _розбір_доповнення_v1(текст, до_вибору=True, попередній_вердикт=None):
    """Розбір форми доповнення (ремонт повноти)."""
    import pipeline as _PL
    if до_вибору:
        _дп = _ПР.розбір_за_схемою(текст, "ДОПОВНЕННЯ_V1")[0]
        _дп = _PL.доповнити(_дп, попередній_вердикт) if isinstance(_дп, dict) else None
        _об_дв = _дп[0] if _дп else _ПР.розбір_за_схемою(текст, "ОБРАЗИ_V1")[0]
        _зл = (_PL.злити_з_неторканими(_об_дв, попередній_вердикт)
               if isinstance(_об_дв, dict) else None)
        if _зл:
            return _зл[0], _зл[1]
        return None, None
    else:
        _дп_пв = _ПР.розбір_за_схемою(текст, "ДОПОВНЕННЯ_V1")[0]
        _дп_пв = _PL.доповнити_обраний(_дп_пв, попередній_вердикт) if isinstance(_дп_пв, dict) else None
        if _дп_пв:
            return _дп_пв[0], None
        _об_пв = _ПР.розбір_за_схемою(текст, "ОБРАЗИ_V1")[0]
        _дн = _PL.донести_ходи_кодом(_об_пв, попередній_вердикт) if isinstance(_об_пв, dict) else None
        if _дн:
            return _дн, None
        return None, None


def _розбір_опис_відповідь_v1(текст, кандидати=None, каталог=None, склад=None, запасні=False):
    """Розбір опису відповіді з JSON."""
    import pipeline as _PL
    _опис_відп = _PL.опис_відповідь_з_json(
        текст, кандидати=кандидати, каталог=каталог, склад=склад, запасні=запасні
    )
    if _опис_відп.get("заміна") and not запасні:
        _опис_відп = _PL.без_прози_заміни(_опис_відп)
    return _опис_відп


def _розбір_руки_без_коду(текст, T=None, перелік=None, паспорт=None):
    """Розбір відповіді руки без коду (проза або перелік); проза без мітки задачі — у `проза_руки`."""
    import pipeline as _PL
    import руки_без_коду as _РБК
    import річ_з_фото as _РФ

    проза = _РБК.проза_руки(текст)
    в = _PL.перевірити_образ_моделі(проза, T, перелік=перелік)
    в["проза_руки"] = проза
    в["джерело_образу"] = (
        "текст моделі (без каталогу), речі — окремим викликом"
        if (в.get("розбір") or {}).get("перелік_моделі")
        else "текст моделі (без каталогу), речі — розбором прози"
    )
    _рр, _стан_її = _РФ.впізнати_в_тексті(в.get("речі"), (паспорт or {}).get("речі_з_фото"))
    if _стан_її:
        в["речі"], в["її_річ"] = _рр, _стан_її
    return в


def _розбір_вибір_речей(вибір_речей, пак=None, сцен=None, сід=None, межі=None):
    """Розбір кроку уважного вибору."""
    import уважний_вибір as _УВ
    return _УВ.крок(вибір_речей, пак, сцен, сід, межі=межі)


def _розбір_заміна(d, пак=None, сцен=None, сід=None):
    """Розбір кроку заміни речі."""
    import заміна_речі as _ЗР
    if пак is None:
        return _ЗР.без_каталогу(d)
    return _ЗР.крок(d, пак, сцен, сід)


def _сторож_outfit_review(об, суд_=None, причина=None, нотатки=None):
    """Сторож оцінки образу: валідація вердикту, works, change проти суду коду."""
    import оцінка_образу as _ОО
    return _ОО.сторож_оцінки_об(об, суд_, причина=причина, нотатки=нотатки)


# ── СХЕМИ З РОЗБОРОМ І СТОРОЖЕМ ───────────────────────────────────────────────
# Розбір і сторож форм, що стоять вище за опис форми; решта — як в описі (`схема_відповіді.СХЕМИ_ВІДПОВІДІ`).
РОЗБІР = {
    "ОБРАЗИ_V1": dict(розбір=_розбір_образи_v1),
    "ВИБІР_V1": dict(розбір=_розбір_вибір_v1),
    "ДОПОВНЕННЯ_V1": dict(розбір=_розбір_доповнення_v1),
    "ОПИС_ВІДПОВІДЬ_V1": dict(розбір=_розбір_опис_відповідь_v1),
    "рука_без_коду": dict(розбір=_розбір_руки_без_коду),
    "вибір_речей": dict(розбір=_розбір_вибір_речей),
    "ЗАМІНА": dict(розбір=_розбір_заміна),
    "ЗАМІНА_БЕЗ_КАТАЛОГУ": dict(розбір=_розбір_заміна),
    "OUTFIT_REVIEW_V1": dict(сторож=_сторож_outfit_review),
}
СХЕМИ_ВІДПОВІДІ = {к: _dc.replace(с, **РОЗБІР.get(к, {})) for к, с in _СВ.СХЕМИ_ВІДПОВІДІ.items()}


def схема_за_назвою(назва):
    """Схема відповіді з розбором і сторожем — та, яку знаходить `схема_відповіді.схема_за_назвою`."""
    return СХЕМИ_ВІДПОВІДІ[_СВ.схема_за_назвою(назва).назва]


def визначити_схему(d):
    """Форма відповіді моделі за входом виклику (`схема_відповіді.визначити_схему`) — з розбором і сторожем."""
    return СХЕМИ_ВІДПОВІДІ[_СВ.визначити_схему(d).назва]
