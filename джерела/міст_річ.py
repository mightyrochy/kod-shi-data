def річ_з_фото(вхід):
    """{…вхід показу…, паспорт, річ: ід, пікселі?} → {ід, вимір, вердикт};
    `пікселі_фото` {ід фото: кадр тієї самої рамки} — інші фото її репліки (рядок 3691): річ, що там міряє слово
    стилістки, переходить на те фото (`фото`, `фото_моделі` у відповіді).
    {репліка} → «невідомо» (рядок 157; з Ч-4 маршрут репліки вирішує мовний шар, показ сюди не кличе);
    {опис_фото: «промпт»|«відповідь», фото, власні?, відповідь_моделі?, паспорт?} → опис речей із
    фото своєю задачею (П-1).

    Колір міряється, коли прийшли пікселі; коли не прийшли — береться вимір, що вже
    лежить у паспорті, а без нього вердикт стоїть на слові кольору моделі як ЗОНІ, і
    це сказано (`вердикт.колір`, чекліст «без входу: колір»)."""
    d = _json.loads(вхід) if isinstance(вхід, str) else вхід
    if "опис_фото" in d:
        # ТРЕТІЙ ВХІД (П-1, 26.09.2026): що на фото її речей — своя задача збирача англійською.
        # «промпт» → {промпт}; «відповідь» → {речі_з_фото, незнайомі, причина}, злите з паспортом.
        if d["опис_фото"] == "промпт":
            return _json.dumps(dict(промпт=_РФ.промпт_фото(d.get("фото"), d.get("власні"), d.get("помилка_формату"))),
                               ensure_ascii=False)
        п = d.get("паспорт") if isinstance(d.get("паспорт"), dict) else {}
        return _json.dumps(_РФ.речі_з_відповіді_фото(d.get("відповідь_моделі"), d.get("фото"),
                                                   п.get("речі_з_фото"), d.get("власні")),
                           ensure_ascii=False, default=str)
    if "репліка" in d:
        # ДРУГИЙ ВХІД (рядок 157): репліка поза сценарієм — чи йде вона в сценарій. Доти це
        # вирішували регулярки її слів (`довідка_репліка`); з Ч-4 її слова тлумачить лише мовна
        # модель шару, і показ сюди вже не кличе. Старому викликачеві — чесне «невідомо».
        return _json.dumps(dict(до_сценарію=False, чому="без мовної моделі шару код її слів не читає — "
                                "«невідомо»: репліка лишається питанням до помічниці", речі=[]),
                           ensure_ascii=False)
    п = d.get("паспорт") if isinstance(d.get("паспорт"), dict) else {}
    ід = str(d.get("річ") or "")
    річ = next((р for р in (п.get("речі_з_фото") or []) if isinstance(р, dict) and р.get("ід") == ід), None)
    if річ is None:
        return _json.dumps(dict(ід=ід, помилка="у паспорті нема речі з фото «%s»" % ід), ensure_ascii=False)
    d = _нормалізувати_вхід(_застосувати_паспорт(d))
    F, T, _зріст, _kw = _збірка(d)
    вимір, перенос = річ.get("вимір"), {}
    шкіра = (F.get("шкіра") or {}).get("hex")
    if d.get("пікселі"):
        вимір = _РФ.виміряти(d["пікселі"], слово_моделі=річ.get("колір"), шкіра_hex=шкіра, рамка=річ.get("рамка"))
    # РЯДОК 3691: кілька фото в одній репліці — та сама рамка на інших фото тієї репліки (`пікселі_фото`), як в
    # оцінці (рядок 3460): вимір розійшовся з її словом, а рамка міряє його рівно на одному іншому фото — річ на тому
    # фото. Ід лишається (злиття паспорта поключове), фото стилістки — полем `фото_моделі`, не мовчки.
    if (вимір or {}).get("спір") and d.get("пікселі") and d.get("пікселі_фото"):
        ф, вим = _РФ.фото_за_словом(d["пікселі_фото"], річ.get("колір"), шкіра_hex=шкіра, рамка=річ.get("рамка"))
        if ф:
            вимір, перенос = вим, dict(фото=ф, фото_моделі=річ.get("фото"))
            річ = dict(річ, **перенос)
    сцен, _незн = СЦ.з_показу(d.get("сценарій") or {}, п)
    вердикт = _РФ.суд_у_виклику(dict(річ, вимір=вимір), F, T, сцен, п,
                                source=d.get("source") or "uncontrolled",
                                intent=(d.get("намір") or "conventional"))
    # КОДИ СЛОТА Й ВИДУ РЕЧІ — внутрішньою мовою (п.12): репліка називає річ кодами, не словом
    _ВМ = _РФ._ВМ
    коди = dict(slot=_ВМ.код_або_невідомо("slot", річ.get("слот")),
                item_type=(річ.get("вид") or _ВМ.UNKNOWN))
    return _json.dumps(dict(ід=ід, вимір=вимір, вердикт=вердикт, коди=коди, **перенос), ensure_ascii=False, default=str)


def судження(d):
    """Лінивий суддя речі з фото для ЦЬОГО виклику: `річ → вердикт` з рисами, тілом і нагодою
    входу `d` — тими самими, що в ендпойнті `річ_з_фото` (картка кличе його в `міст_опис.показ`)."""
    п = d.get("паспорт") if isinstance(d.get("паспорт"), dict) else {}
    стан = {}

    def _суд(річ):
        """Вердикт коду над однією річчю паспорта; риси рахуються один раз на виклик."""
        if not стан:
            дд = _нормалізувати_вхід(_застосувати_паспорт(dict(d)))
            стан["F"], стан["T"], _з, _kw = _збірка(дд)
            стан["сцен"] = СЦ.з_показу(дд.get("сценарій") or {}, п)[0]
            стан["source"], стан["intent"] = дд.get("source") or "uncontrolled", дд.get("намір") or "conventional"
        return _РФ.суд_у_виклику(річ, стан["F"], стан["T"], стан["сцен"], п,
                                 source=стан["source"], intent=стан["intent"])
    return _суд

