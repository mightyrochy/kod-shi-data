# -*- coding: utf-8 -*-
"""міст_річ.py — річ з фото в розмові (рядок 152): ендпойнт `річ_з_фото` — вимір кольору
пікселями й вердикт коду «чи підійде».

ЧОМУ ОКРЕМИЙ МОДУЛЬ МОСТУ. Решта мостових модулів — чисте перенесення з `bridge.py`
(хвиля стандарту, п.16), і їхні функції звіряють проби поділу байт у байт. Новий
ендпойнт туди не дописується: він нового рядка дошки, а не перенесеної логіки.

ПОРЯДОК ВИКЛИКУ. Показ кличе його ПІСЛЯ виклику 0: модель назвала річ і рамку, показ
вирізав рамку з фото на телефоні й зменшив кадр (`пікселіРечіП`), і тут код міряє колір
та судить річ. Повторний виклик без пікселів (вимір уже лежить у паспорті) перераховує
лише вердикт — коли жінка назвала нагоду чи погоду вже після фото."""
import json as _json
import сценарій as СЦ
import паспорт_нагоди as _ПН
import річ_з_фото as _РФ
from міст_вхід import _збірка, _нормалізувати_вхід, _застосувати_паспорт

# Поля, які пише ПОКАЗ (JS), а читає цей шов і `міст_вхід.паспорт`: сканер .py їхнього
# писаря не бачить, тож вони оголошені тут поіменно з місцем у показі.
ЗОВНІШНІ_ВХОДИ = {
 "пікселі": "вхід із показу (`пікселіРечіП`): кадр речі з фото, вирізаний за рамкою моделі й "
            "зменшений до ≤128 px, — {дані: base64url RGB, ширина, висота}; колір міряє `річ_з_фото.виміряти`",
 "річ": "вхід із показу (`оцінитиРечіЗФотоП`): ід речі з фото в паспорті («ф1», «ф1·2»), яку судити",
 "фото_речей": "вхід із показу (`паспортПоРозмовіП`): фото речей нової репліки [{ід, ширина, висота}] — "
               "самі зображення їдуть у виклик 0 блоками; читає `міст_вхід.паспорт`",
}


def річ_з_фото(вхід):
    """{…вхід показу…, паспорт, річ: ід, пікселі?} → {ід, вимір, вердикт}.

    Колір міряється, коли прийшли пікселі; коли не прийшли — береться вимір, що вже
    лежить у паспорті, а без нього вердикт стоїть на слові кольору моделі як ЗОНІ, і
    це сказано (`вердикт.колір`, чекліст «без входу: колір»)."""
    d = _json.loads(вхід) if isinstance(вхід, str) else вхід
    п = d.get("паспорт") if isinstance(d.get("паспорт"), dict) else {}
    ід = str(d.get("річ") or "")
    річ = next((р for р in (п.get("речі_з_фото") or []) if isinstance(р, dict) and р.get("ід") == ід), None)
    if річ is None:
        return _json.dumps(dict(ід=ід, помилка="у паспорті нема речі з фото «%s»" % ід), ensure_ascii=False)
    d = _нормалізувати_вхід(_застосувати_паспорт(d))
    F, T, _зріст, _kw = _збірка(d)
    вимір = річ.get("вимір")
    if d.get("пікселі"):
        вимір = _РФ.виміряти(d["пікселі"], слово_моделі=річ.get("колір"),
                             шкіра_hex=(F.get("шкіра") or {}).get("hex"), рамка=річ.get("рамка"))
    сцен, _незн = СЦ.з_показу(d.get("сценарій") or {}, п)
    типова = (п.get("джерело_полів") or {}).get("нагода") == _ПН.ТИПОВА_НАГОДА_РЕЧІ
    вердикт = _РФ.вердикт(dict(річ, вимір=вимір), F, T, сцен,
                          source=d.get("source") or "uncontrolled",
                          intent=(d.get("намір") or "conventional"), типова_нагода=типова)
    return _json.dumps(dict(ід=ід, вимір=вимір, вердикт=вердикт), ensure_ascii=False, default=str)

