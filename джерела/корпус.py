# -*- coding: utf-8 -*-
"""ДЕ ЛЕЖИТЬ КОРПУС — одна відповідь на питання, яке троє приладів питали окремо.

ЧОМУ ЦЕЙ ФАЙЛ ІСНУЄ. Пошук тем був списаний утретє, і дві з трьох копій були
мертві: `gate_reach` і `rule_genus` мали зашитий `/mnt/project` без запасного
шляху, тож поза тією однією машиною гейт досяжності мовчки не запускався, а
звірка двох читачів корпусу друкувала «НЕ ЗВІРЕНО». Прилад, який не працює
ніде, крім авторської теки, — це не прилад.

ТРЕТЯ КОПІЯ БУЛА ПРАВИЛЬНА, І САМЕ ВОНА ТУТ. `audit_contracts` уже ніс ланцюг
кандидатів і правило вибору: береться ПЕРША тека, у якій справді є файли тем.
Перевірка вмістом, а не існуванням теки, тут не педантизм: порожня тека, що
існує, дала б нуль правил і звіт «жодне правило не в корпусі» — тобто найгіршу
з можливих відповідей, бо вона схожа на вимір.

ЩО ЦЕЙ ФАЙЛ НЕ РОБИТЬ. Не читає блоків правил і не судить, що правило означає:
розбір блоку живе в `звірка.py`, і тримати два розбирачі означало б завести
двійника, від якого проєкт уже страждав. Тут лише: де теми, які вони, які ID у
них є.
"""
import os
import re

import ід_правил as ІП

# Ім'я змінної ASCII навмисно: кирилиця в іменах змінних середовища ламає sh
# і .bat — той самий урок, що вже коштував проєкту прогону жниварки.
ЗМІННА = "LUSTERKO_CORPUS"

# Префікс, а не список імен: список довелося б дописувати з кожною новою темою,
# і саме так у проєкті вже губились файли (доказ — `audit_contracts._живі_модулі`).
ПРЕФІКСИ_ТЕМ = ("тема-", "topic-")

# ШАБЛОН ID ТУТ БІЛЬШЕ НЕ ЖИВЕ (10.09.2026). Він був списаний уп'яте, і жодні
# дві копії не збігались: `[KRE]` тут проти `[KR]` у гейті цілей образів давали
# різні знаменники в двох звітах про одне й те саме. Тепер шаблон один —
# `ід_правил`, — і назви `ID_ПРАВИЛА` тут навмисно НЕМА: викликач, який далі
# кличе `.findall`, має впасти гучно, а не дістати мовчки пари (база, суфікс).
бази_в_тексті = ІП.бази_в_тексті

_ТУТ = os.path.dirname(os.path.abspath(__file__))


def кандидати():
    """Теки-кандидати за спаданням пріоритету. Змінна середовища — перша."""
    з_середовища = os.environ.get(ЗМІННА)
    return tuple(x for x in (з_середовища, ".", "..", _ТУТ, "/mnt/project") if x)


def тека(шлях=None):
    """Перша тека, у якій СПРАВДІ є файли тем. None, якщо корпусу не видно.

    None, а не виняток: викликач — прилад, і він мусить мати змогу сказати
    «корпусу не видно» замість того, щоб упасти й лишити решту вимірів незнятими.
    """
    if шлях:
        return шлях if _має_теми(шлях) else None
    for к in кандидати():
        if _має_теми(к):
            return к
    return None


def _має_теми(шлях):
    try:
        return any(f.startswith(ПРЕФІКСИ_ТЕМ) and f.endswith(".md")
                   for f in os.listdir(шлях))
    except OSError:
        return False


def файли(шлях=None):
    """(файли-теми, решта .md) — обидва списки видимі викликачеві.

    Друга половина не сміття: документи про систему (звірки, карти, матриці)
    лежать поруч із темами, і прилад мусить бачити, що саме він пропустив.
    """
    т = тека(шлях)
    if not т:
        return [], []
    md = sorted(f for f in os.listdir(т) if f.endswith(".md"))
    теми = [f for f in md if f.startswith(ПРЕФІКСИ_ТЕМ)]
    return теми, [f for f in md if f not in теми]


def текст(шлях=None):
    """{ім'я теми: текст}. Читається один раз на прогін приладу."""
    т = тека(шлях)
    if not т:
        return {}
    out = {}
    for f in файли(т)[0]:
        with open(os.path.join(т, f), encoding="utf-8", errors="replace") as fh:
            out[f] = fh.read()
    return out


def ід(шлях=None):
    """Множина ID правил, згаданих у темах."""
    з = set()
    for т in текст(шлях).values():
        з |= бази_в_тексті(т)
    return з


def ід_поза_корпусом(цитовані, шлях=None):
    """{ID: причина} — ті з `цитовані`, кого НЕ називає ЖОДНА тема.

    ОДИН КРИТЕРІЙ, І ЦЕ ГОЛОВНЕ. «Поза корпусом» рахувалось трьома різними
    способами: `outfit.ПОЗА_КОРПУСОМ` — ручний словник «нема в зведеному реєстрі»
    (реєстру не існує з 24.08), `rule_genus.поза_корпусом` — фільтр того ж
    словника проти корпусу, `audit_contracts` — звірка словника з темами в обидва
    боки. Три відповіді розійшлись рівно так, як розходяться всі копії в цьому
    проєкті: пʼять ID у словнику теми ВЖЕ називали (і знахідка виходила стилістці
    з хибним «⚠ ПОЗА КОРПУСОМ»), девʼятьох у словнику не було зовсім. Тепер
    критерій один і механічний: згадка в `тема-*.md` є або її нема.

    ЩО ЦЕ НЕ МІРЯЄ. Згадка ≠ означення: тема може згадати ID перехресним
    посиланням («корпус уже має R-HELM-03») і не означити його. Це ОКРЕМЕ
    питання, і воно тут навмисно не вирішується — див. `ід_без_означення`.
    """
    корп = ід(шлях)
    return {c: "жодна тема не називає цей ID"
            for c in sorted(цитовані) if c not in корп}


def ід_без_означення(цитовані, означені, шлях=None):
    """{ID: [теми, що його називають]} — згадані, але серед `означені` їх нема.

    ТРЕТІЙ СТАН, ЯКИЙ ЗЛИВАВСЯ З ДВОМА ІНШИМИ. «Є в темі» і «нема ніде» —
    не вичерпний поділ: між ними ID, який тема НАЗИВАЄ, але не ОЗНАЧУЄ. Саме
    сюди попали пʼять записів старого ручного словника, і саме через них звірка
    в обидва боки давала суперечливі вироки.

    `означені` подає ВИКЛИКАЧ (`правила.формулювання` — єдиний калібрований
    розпізнавач форми означення в проєкті). Цей файл навмисно не судить, що
    правило означає: розбір блоку живе не тут, і другий розбирач був би тим
    самим двійником, від якого лікується решта.
    """
    де = {}
    for імя, т in sorted(текст(шлях).items()):
        for i in бази_в_тексті(т):
            де.setdefault(i, []).append(імя)
    return {c: де[c] for c in sorted(цитовані) if c in де and c not in означені}


