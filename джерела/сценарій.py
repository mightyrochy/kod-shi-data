СМУГА_З_БАЛА = {"0": "calm", "1": "moderate", "2": "strong"}   # бал плитки показу → смуга (порядковий, не м/с)
СИЛЬНИЙ_ВІТЕР = "strong"


def смуга_вітру(v):
    """Код смуги вітру або None; число, слово поза переліком і порожнє — None («про вітер не сказано»)."""
    return v if isinstance(v, str) and v in СМУГИ_ВІТРУ else None


def вітер_є(v):
    """Чи є вітрове навантаження (K-OUT-13): відома смуга, крім `calm`."""
    return смуга_вітру(v) not in (None, "calm")


def вітер_словами(v):
    """Назва смуги вітру для показу; незнайомий код не стає вітром."""
    return {"calm": "безвітря", "moderate": "помірний", "strong": "сильний"}.get(смуга_вітру(v), "невідомо")


def канон_опади(v, смуга_погоди=None):
    """Код опадів → сталий ключ ядра; незнайомий код і відсутній вхід → None.

    Сумісність старих записів обмежена кодами «так» і «нема», без словника слів.
    Грубе «так» не визначає виду опадів: його має назвати модель.
    """
    if not isinstance(v, str):
        return None
    if v in ОПАДИ_КОДИ:
        return ОПАДИ_КОДИ[v]
    v = v.strip().lower()
    if v == "так":
        return None
    if v == "нема":
        return ОПАДИ_НІ
    return v if v in ОПАДИ_КАНОН else None


def опади_поверх(плитка, паспорт, смуга_погоди=None):
    """Яке слово лишається, коли про опади говорять обидва джерела.

    Загальне правило шва («слова людини — перші») лишається; знято лише його
    побічний наслідок — ВТРАТА ТОЧНОСТІ. Грубе паспортове «так» і плиткове
    «дощ»/«сніг» кажуть ОДНЕ Й ТЕ САМЕ («мокро»), і тоді виграє те джерело, яке
    каже більше. Незгода («так» проти «ні») — не втрата точності, і там паспорт
    як і доти переважає."""
    п, т = канон_опади(паспорт, смуга_погоди), канон_опади(плитка, смуга_погоди)
    if п is None:
        return т
    грубе = str(паспорт).strip().lower() in ГРУБІ_ОПАДИ
    if грубе and п != ОПАДИ_НІ and т is not None and т != ОПАДИ_НІ:
        return т
    return п


# ── ВІТЕР З ЕКРАНА ДОЇЖДЖАЄ ДО КОДУ (П-1) ───────────────────────────────────
# Плитка «Вітер» шле бал своїм іменем (`вітер_бал`, `ЗОВНІШНІ_ВХОДИ` вище); смугу за ним ставить один шов —
# `паспорт_нагоди.з_показу`. Явна смуга від викликача переважає бал плитки — як на опадах («джерело, яке каже більше»).
def смуга_з_бала(бал):
    """Бал плитки показу (0/1/2) → код смуги вітру, або None, коли бала нема чи він поза шкалою (п.14)."""
    if isinstance(бал, bool) or бал in (None, ""):
        return None
    if isinstance(бал, float) and бал.is_integer():
        бал = int(бал)
    return СМУГА_З_БАЛА.get(str(бал).strip())


