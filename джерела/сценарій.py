def канон_опади(v):
    """Сире слово опадів → одне з `ОПАДИ_КАНОН`, або None («невідомо»/не сказано).

    None — не «сухо»: погодні правила на ньому мовчать, і це навмисно (погода не
    вигадується, `суд_образу.погода`)."""
    if v in (None, "", False):
        return None
    с = str(v).strip().lower()
    if с in ("невідомо", "?"):
        return None
    с = _ОПАДИ_СИНОНІМИ.get(с, с)
    с = ГРУБІ_ОПАДИ.get(с, с)
    return с if с in ОПАДИ_КАНОН else None


