# Шов їх зіштовхував: `з_показу` клала грубе паспортове «так» ПОВЕРХ плиткового
# «дощ», а всі ворота матеріалу (K-WEA-01 тут, K-WEA-05 в `accessory`, сльота в
# `outer`) питають рівно конкретне слово. Виміряно 19.09.2026 на пробі
# `аудит/проби/рв3_опади.py`: «дощ» → K-WEA-01 2 знахідки, «так» → 1 (стільки ж,
# скільки «ні»), тобто слово людини «так, дощ» гасило вето замші.
# Тому переклад тепер ОДИН і стоїть на шві, а не в кожному споживачеві.
ОПАДИ_НІ = "ні"                                      # так його знає `composer` (рядок 1137)
МОКРІ_ОПАДИ = ("дощ", "мокрий_сніг", "злива")        # ворота матеріалу K-WEA-01/05
СОЛЬОВІ_ОПАДИ = ("мокрий_сніг", "сніг")              # сльота й реагенти (`outer._сльота`)
МОЖЛИВИЙ_ДОЩ = "можливий_дощ"                   # ймовірність: не мокрий день і не вето
ОПАДИ_КАНОН = (ОПАДИ_НІ, МОЖЛИВИЙ_ДОЩ) + МОКРІ_ОПАДИ + ("сніг",)
# ГРУБЕ СЛОВО ПАСПОРТА — не синонім, а ІНША ТОЧНІСТЬ: воно каже «мокро/сухо», не
# називаючи опадів. «так» читається як ДОЩ, і це рішення, а не здогад: корпус
# (тема-4:522 «FORCE: hard», тема-10:1571) тримає дощ як абсолютну межу тканини
# й взуття, а мовчання на «так» означало б, що система вважає сухо там, де людина
# сказала «мокро».
# «ТАК» ПРИ ≤ 0 °C — СНІГ (24.09.2026, рядок 205). Доти сніг із «так» не виводився
# («домальовувати температурою — вигадка»), і показ робив це сам, питаючи плитку.
# Наслідок: той самий паспорт «опади: так, −8 °C» давав через показ «сніг», а повз
# показ (модель, міст, пряма проба) — «дощ», і картка казала «Замша у дощ…» у мороз.
# При ≤ 0 °C дощ — не той опад, про який людина каже «так» (вода замерзає); слово
# тепер одне для всіх входів і виводиться ТУТ, на шві, з температурою дня.
ГРУБІ_ОПАДИ = {"так": "дощ", "ні": ОПАДИ_НІ}
СНІГ_ДО_C = 0.0          # «так» при температурі не вище цієї — сніг, а не дощ
_ОПАДИ_СИНОНІМИ = {"можливий дощ": МОЖЛИВИЙ_ДОЩ, "нема": ОПАДИ_НІ, "немає": ОПАДИ_НІ, "без опадів": ОПАДИ_НІ,
                   "мокрий сніг": "мокрий_сніг", "мокрий-сніг": "мокрий_сніг"}


def канон_опади(v, темп_c=None):
    """Сире слово опадів → одне з `ОПАДИ_КАНОН`, або None («невідомо»/не сказано).

    None — не «сухо»: погодні правила на ньому мовчать, і це навмисно (погода не
    вигадується, `суд_образу.погода`)."""
    if v in (None, "", False):
        return None
    с = str(v).strip().lower()
    if с in ("невідомо", "?"):
        return None
    с = _ОПАДИ_СИНОНІМИ.get(с, с)
    if с == "так" and темп_c not in (None, "") and float(темп_c) <= СНІГ_ДО_C:
        return "сніг"
    с = ГРУБІ_ОПАДИ.get(с, с)
    return с if с in ОПАДИ_КАНОН else None


def опади_поверх(плитка, паспорт, темп_c=None):
    """Яке слово лишається, коли про опади говорять обидва джерела.

    Загальне правило шва («слова людини — перші») лишається; знято лише його
    побічний наслідок — ВТРАТА ТОЧНОСТІ. Грубе паспортове «так» і плиткове
    «дощ»/«сніг» кажуть ОДНЕ Й ТЕ САМЕ («мокро»), і тоді виграє те джерело, яке
    каже більше. Незгода («так» проти «ні») — не втрата точності, і там паспорт
    як і доти переважає."""
    п, т = канон_опади(паспорт, темп_c), канон_опади(плитка, темп_c)
    if п is None:
        return т
    грубе = str(паспорт).strip().lower() in ГРУБІ_ОПАДИ
    if грубе and п != ОПАДИ_НІ and т is not None and т != ОПАДИ_НІ:
        return т
    return п


