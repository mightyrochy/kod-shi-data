def з_показу(с, паспорт=None):
    """(нагода, незнайомі) — з того, що прийшло від показу, і з паспорта випадку.

    Паспорт ПЕРЕВАЖАЄ вибраний сценарій: він зібраний зі слів людини про цю
    конкретну подію, а сценарій — з випадаючого списку. Це та сама асиметрія,
    що вже стоїть у `composer` для ошатності («слова людини — перші»).

    Незнайомі ключі не відкидаються мовчки: вони повертаються другим значенням.
    Викликач вирішує, показати їх чи знехтувати, — але не може НЕ ЗНАТИ про них.
    """
    с = dict(с or {})
    п = dict(паспорт or {})
    нагода, незнайомі = {}, []
    for k, v in с.items():
        if v in (None, ""):
            continue
        if k in ПОЛЯ or k in СЛУЖБОВІ:
            нагода[k] = v
        else:
            незнайомі.append(k)
    for k in ПОЛЯ:
        v = п.get(k)
        if v not in (None, "") and v != "невідомо":
            нагода[k] = v
    return нагода, sorted(незнайомі)


