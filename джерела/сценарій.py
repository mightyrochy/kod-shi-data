# ЩО БУЛО. Плитка «Вітер» на екрані сценарію має три бали — безвітря / помірний /
# сильний — і показ слав САМ БАЛ під іменем `вітер`: 0, 1, 2 (`зібратиВхід`,
# `parseFloat`). Усі три споживачі поля чекають МЕТРІВ НА СЕКУНДУ:
# `композитор_збирання` тримає слот верхнього шару від 6 м/с, `суд_погода` судить
# легкий кльош від 8 м/с, `день_кодами` віддає моделі `wind_ms` від
# `ВІТЕР_ПОМІТНИЙ` = 6. Отже «сильний вітер» приходив числом 2 і не вмикав НІЧОГО:
# шар не тримався, кльош не судився, модель вітру не бачила зовсім. Бал 2 і 2 м/с —
# різні величини під одним іменем, і саме це робило поле мертвим.
# ЩО ТЕПЕР. Екран шле бал своїм іменем (`вітер_бал`, `ЗОВНІШНІ_ВХОДИ` вище), а
# переклад бала в м/с стоїть В ОДНОМУ МІСЦІ — тут, на шві, куди приходить усе, що
# каже показ. Поле `вітер` лишається тим, чим його оголошено й чим його читають
# споживачі й проби (`wea_K-WEA-05`: 5, `out_K-OUT-19`: 8, стенд: 8) — м/с.
# ЧИСЛА ШКАЛИ — КОНВЕНЦІЯ, НЕ ВИМІР: шкала Бофорта зве 3–5 м/с легким вітерцем, а
# 8–10 м/с — свіжим, який уже «підіймає пил і рве поділ». Беремо середину кожної:
# помірний 5, сильний 10. «Помірний» НАВМИСНО нижчий за 6 м/с — тобто шару він не
# тримає й моделі не їде: плитка «помірний» не мусить робити те саме, що «сильний»,
# інакше три бали означали б два.
# ЯВНЕ СЛОВО ПЕРЕВАЖАЄ ШКАЛУ: коли викликач (проба, стенд, прилад, майбутній
# прогноз) подав `вітер` числом сам, бал його не чіпає — той самий принцип, що вже
# стоїть на опадах («джерело, яке каже більше»).
ВІТЕР_БАЛИ = {0: 0.0, 1: 5.0, 2: 10.0}   # бал плитки показу → м/с (конвенція, Бофорт)


def вітер_мс(бал):
    """Бал шкали показу (0/1/2) → м/с, або None, коли бала нема чи він поза шкалою.

    None — «про вітер не сказано»: погодні правила на ньому мовчать, як і на
    відсутній температурі. Нечислове поле — теж None, а не поломка коду (п.14)."""
    if бал in (None, ""):
        return None
    try:
        return ВІТЕР_БАЛИ.get(int(float(бал)))
    except (TypeError, ValueError):
        return None


def з_показу(с, паспорт=None):
    """(нагода, незнайомі) — з того, що прийшло від показу, і з паспорта випадку.

    Паспорт ПЕРЕВАЖАЄ вибраний сценарій: він зібраний зі слів людини про цю
    конкретну подію, а сценарій — з випадаючого списку. Це та сама асиметрія,
    що вже стоїть у `composer` для ошатності («слова людини — перші»).

    Незнайомі ключі не відкидаються мовчки: вони повертаються другим значенням.
    Викликач вирішує, показати їх чи знехтувати, — але не може НЕ ЗНАТИ про них.
    """
    с = dict(с or {})
    п = dict(паспорт or {})
    нагода, незнайомі = {}, []
    for k, v in с.items():
        if v in (None, ""):
            continue
        if k in ПОЛЯ or k in СЛУЖБОВІ:
            нагода[k] = v
        else:
            незнайомі.append(k)
    for k in ПОЛЯ:
        v = п.get(k)
        if v not in (None, "") and v != "невідомо":
            нагода[k] = v
    # ── ЗАМОВЧУВАННЯ ФОРМИ — «НЕВІДОМО» І ДЛЯ ПРАВИЛ (ТИПОВЕ-1, дошка 1406–1408) ──────
    # ЩО БУЛО. 11:00, +18 °C і типове місце плитки, яких вона не називала (`типові_поля`),
    # не їхали фактом її дня моделям, але правила рахували ними, як її словами: +18 °C знімали
    # з пулу всі босоніжки й сандалі (0 у 40 з 40 прогонів розбору 02.10, 159–292 пари на
    # прогін), 11:00 вмикали `day_outing` на новорічному корпоративі, а місце плитки
    # «весілля вечірнє» стояло над її «весіллям удень». ЩО ТЕПЕР (п.12: «невідомо» замість
    # вигадки). Поле з переліку лишається, лише коли паспорт несе його зі слів — її чи
    # почутих моделлю (`джерело_полів` не `типове_форми`); інакше його в нагоді нема: відсів
    # за ним не працює, вісь «день/вечір» не вмикається, а модель бачить «невідомо».
    import паспорт_нагоди as _ПН
    _дж = п.get("джерело_полів") or {}
    for k in _ПН.типові_поля_форми(с):
        if п.get(k) in (None, "", "невідомо") or _дж.get(k) == _ПН.ТИПОВЕ_ПОЛЕ_ФОРМИ:
            нагода.pop(k, None)
    # Опади — єдине поле, де два джерела говорять РІЗНОЮ ТОЧНІСТЮ (див. вище).
    # Канон ставиться навіть тоді, коли паспорт мовчить: далі по шву стоять
    # споживачі («нема» плитки проти «ні» композитора), і слово має бути одне.
    if "опади" in нагода or п.get("опади") not in (None, ""):
        _оп = опади_поверх(с.get("опади"), п.get("опади"), нагода.get("темп_c"))
        if _оп is None:
            нагода.pop("опади", None)
        else:
            нагода["опади"] = _оп
    # Вітер — бал шкали показу в м/с, і рівно тут (П-1, абзац над `ВІТЕР_БАЛИ`).
    _бал = нагода.pop("вітер_бал", None)
    if нагода.get("вітер") in (None, ""):
        _мс = вітер_мс(_бал)
        if _мс is not None:
            нагода["вітер"] = _мс
    # Дія й поверхня під ногами — лише полем паспорта (`активність`, `поверхня`), яке ставить
    # мовна модель шару кодами `activity` / `surface` на уривку її слів (Ч-4, див. нижче).
    return нагода, sorted(незнайомі)


