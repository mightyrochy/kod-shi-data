# ── СІЛЬ НА ДОРОЗІ — ОДНА ВІДПОВІДЬ ДЛЯ ВОРІТ ЗАМШІ ────────────────────────
# ЩО БУЛО. K-WEA-05 (`аксесуари_погода.сезон_і_погода`) вмикався на `опади` з
# `МОКРІ_ОПАДИ` або на ручному полі `реагенти`. «Так, сніг» з розмови канонізується в
# «сніг» — не мокрий, — а `реагенти` ставить лише ручна плитка «Реагенти на дорогах»,
# з розмови воно не приходить. Отже при −8 °C і снігу замшеві угги й сумка на картці
# не несли жодної умови, хоча корпус (тема-10, K-WEA-07: «−8…2 °C: реагенти → замша й
# нубук вето»; K-WEA-05: «замша й нубук у снігу з реагентами — відмова матеріалу»)
# називає саме цей день.
# ЩО ТЕПЕР. Сіль виводиться з погоди: сніг чи мокрий сніг (`СОЛЬОВІ_ОПАДИ`) при
# температурі не вище верхньої межі смуги K-WEA-07 (+2 °C). Нижню межу смуги (−8 °C)
# не взято: у мороз нижче дороги солять так само, а смуга лише каже, з якої
# температури сіль уже є. Ручна плитка — сильніше слово в обидва боки: «є» — сіль є
# за будь-якої погоди, «нема» — нема, хоч би який сніг.


# ── ОДНЕ ЧИСЛО ПРО ОДИН ДЕНЬ ────────────────────────────────────────────────
# ЩО БУЛО. Температуру дня форматували НЕЗАЛЕЖНО в двох місцях: рядок випадку —
# `"%g °C"` (`паспорт_нагоди`), а суть K-WEA-05 і «звідки» солі — `"%+.0f °C"`.
# На цілому числі вони збігались, на дробовому — ні, і в одному звіті власника
# стояло два різні числа про той самий день (прогін `zlyttia_268_moroz`: у рядку
# випадку одне, у суті K-WEA-05 інше). Дробове береться не з голови: температуру
# в паспорт підставляє МОДЕЛЬ (З-5г — «18 °C» майже в кожен паспорт), і
# `паспорт_з_json` бере її через `float()`. «-0.4 °C» у суті ставало «-0 °C».
# ЩО ТЕПЕР. Один формат на весь день, з одного місця — модуля, який день і
# тримає. Виводить те саме, що доти бачила жінка в рядку випадку (`%g`), тож
# шапка показу не міняється; змінюється те, що суть і «звідки» більше НЕ
# округлюють нишком і не можуть розійтися з рядком випадку.
def сіль_на_дорозі(реагенти=None, смуга_погоди=None, опади=None):
    """(чи є сіль на дорозі, звідки це відомо). Ручне слово `реагенти` («1»/«так»/«є» чи
    «0»/«ні»/«нема») сильніше за вивід; без нього — сніг чи мокрий сніг при ≤ `СІЛЬ_ДО_C`."""
    if реагенти not in (None, ""):
        с = str(реагенти).strip().lower()
        so = с not in ("0", "0.0", "ні", "нема", "немає", "false", "no")
        return so, ("реагенти оголошені рукою: %s" % ("є" if so else "нема"))
    о = канон_опади(опади, смуга_погоди)
    if о in СОЛЬОВІ_ОПАДИ and смуга_погоди in МОРОЗНІ_СМУГИ:
        return True, ("виведено з погоди: «%s» при %s — смуга солі K-WEA-07" % (о, смуга_словами(смуга_погоди)))
    return False, None


# ── СИЛЬНА НЕПОГОДА: КОЛИ ЗАМША ВИХОДИТЬ З ПУЛУ (ВІДСІВ-1) ────────────────
# «Замша — з умовою. За сильної непогоди — тільки якщо людина сама попросить.» K-WEA-05
# (тема-10:1603) дає дві форми: «не пропонується» або «з явною умовою»; звичайний дощ чи мокро
# тепер — друга (замша в пулі, суд ставить умову K-WEA-05), а перша лишається для СИЛЬНОЇ
# непогоди. Поля й пороги — ті, що вже є в паспорті погоди, нових чисел не заводиться:
#   · `опади` = «злива» — найсильніше слово контракту опадів (`profile.ПОГОДА_КОНТРАКТ`);
#     K-WEA-01 (тема-4:522): «Rain … constrain fabric, hem and footwear absolutely»;
#   · `опади` = «мокрий_сніг» і сіль на дорозі (`сіль_на_дорозі`: ручне `реагенти` або вивід
#     ≤ СІЛЬ_ДО_C) — рівно випадок, який K-WEA-05 зве «відмова матеріалу, не смаку»;
#   · мокрі опади й смуга вітру `strong` (плитка «сильний»; Бофорт 6: «парасолькою користуватися важко») —
#     K-WEA-01 «Rain and wind»: косий дощ мочить і те, що під парасолею.
# Поля нема (вітру не сказали, сіль не виводиться) — непогода звичайна, і замша йде з умовою.


def сильна_непогода(опади=None, смуга_погоди=None, реагенти=None, смуга_вітру=None):
    """Код сильної непогоди (`downpour`, `wet_snow_with_salt`, `wet_with_strong_wind`) або None.

    None — сухо, невідомо або звичайна мокра погода (дощ, мокрий сніг без солі, без сильного
    вітру). Провенанс порогів — коментар вище."""
    о = канон_опади(опади, смуга_погоди)
    if о not in МОКРІ_ОПАДИ:
        return None
    if о == "злива":
        return "downpour"
    if о == "мокрий_сніг" and сіль_на_дорозі(реагенти, смуга_погоди, опади)[0]:
        return "wet_snow_with_salt"
    if смуга_вітру == СИЛЬНИЙ_ВІТЕР:
        return "wet_with_strong_wind"
    return None


# ── ЇЇ ДЕНЬ ФАКТАМИ ДЛЯ МОДЕЛІ — ВНУТРІШНЬОЮ МОВОЮ (М-1, аудит/ПРОДУКТ.md п.12) ──
# Без фактів дня прогулянка з собаками в парку, +18 °C, вітер і «багато ходити» може
# отримати світлі палаццо до підлоги й замшеві лофери. Дію й поверхню код уже знав, але до
# моделі доходив один рядок брифа — тож з'явився один опис дня для моделей. Писав його код
# ФРАЗАМИ людською мовою (`ДІЯ_СЛОВАМИ`, `ФОРМАТ_СЛОВАМИ`, `ОПАДИ_СЛОВАМИ`: «прогулянка просто
# неба», «з 18:00 — вечір і до ночі; надворі темно, світло штучне») — мова в коді (п.12:
# «Код напряму спілкується тільки з ші … лише універсальна комп'ютерна мова»).
# ЩО ТЕПЕР. Ті самі факти — кодами й числами внутрішньої мови (`внутрішня_мова.ТАБЛИЦЯ`):
# функціональна модель читає їх сама, жінці вони доходять лише перекладачем. Факти, не
# висновки й не заборони: думати над ними — робота моделі (власник 24.09: «такі речі має
# фільтрувати сам ші, який повинен підходити до образів думаючи»). Читачі — пакет складання,
# вердикт ремонту й вибору, опис обраного образу. Невідоме не вигадується: чого сценарій не
# знає, того ключа нема.
# Поля дня, що несуть код переліку: ключ дня → (поле `внутрішня_мова.ТАБЛИЦЯ`, поле сценарію)
_КОДИ_ДНЯ = (("activity", "activity", "активність"), ("movement", "movement", "рух"),
             ("place", "place", "місце"), ("setting", "setting", "формат"),
             ("surface", "surface", "поверхня"), ("dress_code", "dress_code", "дрес_код"),
             ("weather_band", "weather_band", "смуга_погоди"), ("wind_band", "wind_band", "смуга_вітру"))


def день_кодами(сцен):
    """dict її дня внутрішньою мовою — коди й числа, лише відоме.

    Вхід — сценарій після `з_показу` (там уже дія й поверхня зі слів). Порожній dict —
    сценарій про день не знає нічого. Схема — `протокол.ДЕНЬ`.

    ЗАМОВЧУВАННЯ ФОРМИ — НЕ ФАКТ ЇЇ ДНЯ (В-2). +18 °C і типове місце, яких рука не торкалась і
    яких вона не називала (`типові_поля` показу; поле з її слів показ із цього переліку знімає), правила
    читають, як доти, — але в «день» для моделей вони не йдуть, як і в `case`
    (`пакет_моделі.випадок_для_пакета`). Доти рука 1 діставала в `day` `temperature_c: 18, start_hour:
    11, part_of_day: day, light: daylight` — погоду й годину, яких жінка не казала, фактами її дня.
    Разом із годиною не йде й те, що з неї виведено (частина доби, світло, «до ночі»), а з
    температурою — сіль на дорогах.

    ТИПОВЕ-1: замовчування знімає вже `з_показу` (поле лишається, лише коли паспорт почув його від
    неї — тоді воно її, хоч плитки рука й не торкалась). Тут те, чого вона не назвала, їде фактом
    «невідомо»: `unknown` — ключі дня, які форма стояла типовими й ніхто не назвав."""
    from occasion import потреба_події, виміри_на_дріт, вечірнє_світло
    с = dict(сцен or {})
    типові = {str(x) for x in (с.get("типові_поля") or ())}
    невідоме = [ключ for ім, ключ in (("місце", "place"), ("смуга_погоди", "weather_band"))
                if ім in типові and с.get(ім) in (None, "")]
    число = lambda v: int(v) if float(v).is_integer() else float(v)
    д = {}
    for ключ, поле, ім in _КОДИ_ДНЯ:
        к = _ВМ.код(поле, с.get(ім)) if с.get(ім) not in (None, "", "невідомо") else None
        if к:
            д[ключ] = к
    if с.get("тривалість_год") not in (None, ""):
        д["duration_h"] = число(с["тривалість_год"])
    if _ВМ.код("season", с.get("пора_року")):
        д["season"] = _ВМ.код("season", с["пора_року"])
        д["season_source"] = с.get("пора_року_джерело") or _ПП.походження_поля(с, "пора_року")
    опади = _ВМ.код("precipitation", канон_опади(с.get("опади"))) if с.get("опади") not in (None, "") else None
    if опади:
        д["precipitation"] = опади
    if isinstance(с.get("сонце"), bool):
        д["direct_sun"] = с["сонце"]
    if isinstance(с.get("господар"), bool):
        д["host_context"] = с["господар"]
    if isinstance(с.get("креативне"), bool):
        д["creative_environment"] = с["креативне"]
    if сіль_на_дорозі(с.get("реагенти"), с.get("смуга_погоди"), с.get("опади"))[0]:
        д["road_salt"] = True
    # ЧАСТИНА ДНЯ — ПОРА ВІД МОВНОЇ МОДЕЛІ, НЕ З ГОДИНИ (корінь Е2-частина-дня, крок 1). Доти `part_of_day` рахувала
    # `частина_доби` порогами 5/11/17/22, яких у базі знань нема; тепер її годину частиною дня робить модель
    # Крок 2: година дня в «день» моделей не йде (ні `start_hour`, ні «до ночі» з годин і тривалості), а світло —
    # з частини дня: вечір і ніч — штучне, ранок і день — денне (доти — пороги 20/21, 6, 7–17 від години).
    if _ВМ.код("part_of_day", с.get("пора")):
        д["part_of_day"] = _ВМ.код("part_of_day", с["пора"])
        д["light"] = "artificial" if вечірнє_світло(с["пора"]) else "daylight"
    _о = с.get("_ошатність") or с.get("ошатність")
    if isinstance(_о, (list, tuple)) and len(_о) == 2:
        д["formality"] = {"from": число(_о[0]), "to": число(_о[1])}
    if с:
        д["occasion_requirements"] = виміри_на_дріт(потреба_події(с))
    if невідоме:
        д["unknown"] = невідоме
    return д
