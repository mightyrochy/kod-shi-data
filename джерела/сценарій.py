# ── ОДИН СЛОВНИК ОПАДІВ НА СИСТЕМУ (СТАНДАРТ §4 п.5) ────────────────────────
# Словників було три, і вони не перекладались один в одного:
#   · `протокол.ВИПАДОК` / `pipeline.СХЕМА_ПАСПОРТА` — «так | ні | невідомо»;
#   · `profile.ПОГОДА_КОНТРАКТ` — «немає | дощ | мокрий_сніг | злива | сніг»;
