# ── СІЛЬ НА ДОРОЗІ — ОДНА ВІДПОВІДЬ ДЛЯ ВОРІТ ЗАМШІ (24.09.2026, рядок 186) ────
# ЩО БУЛО. K-WEA-05 (`аксесуари_погода.сезон_і_погода`) вмикався на `опади` з
# `МОКРІ_ОПАДИ` або на ручному полі `реагенти`. «Так, сніг» з розмови канонізується в
# «сніг» — не мокрий, — а `реагенти` ставить лише ручна плитка «Реагенти на дорогах»,
# з розмови воно не приходить. Отже при −8 °C і снігу замшеві угги й сумка на картці
# не несли жодної умови, хоча корпус (тема-10, K-WEA-07: «−8…2 °C: реагенти → замша й
# нубук вето»; K-WEA-05: «замша й нубук у снігу з реагентами — відмова матеріалу»)
# називає саме цей день.
# ЩО ТЕПЕР. Сіль виводиться з погоди: сніг чи мокрий сніг (`СОЛЬОВІ_ОПАДИ`) при
# температурі не вище верхньої межі смуги K-WEA-07 (+2 °C). Нижню межу смуги (−8 °C)
# не взято: у мороз нижче дороги солять так само, а смуга лише каже, з якої
# температури сіль уже є. Ручна плитка — сильніше слово в обидва боки: «є» — сіль є
# за будь-якої погоди, «нема» — нема, хоч би який сніг.
СІЛЬ_ДО_C = 2.0          # верхня межа смуги «−8…2 °C» K-WEA-07 (тема-10, hint)


# ── ОДНЕ ЧИСЛО ПРО ОДИН ДЕНЬ (#268, 24.09.2026) ──────────────────────────────
# ЩО БУЛО. Температуру дня форматували НЕЗАЛЕЖНО в двох місцях: рядок випадку —
# `"%g °C"` (`паспорт_нагоди`), а суть K-WEA-05 і «звідки» солі — `"%+.0f °C"`.
# На цілому числі вони збігались, на дробовому — ні, і в одному звіті власника
# стояло два різні числа про той самий день (прогін `zlyttia_268_moroz`: у рядку
# випадку одне, у суті K-WEA-05 інше). Дробове береться не з голови: температуру
# в паспорт підставляє МОДЕЛЬ (З-5г — «18 °C» майже в кожен паспорт), і
# `паспорт_з_json` бере її через `float()`. «-0.4 °C» у суті ставало «-0 °C».
# ЩО ТЕПЕР. Один формат на весь день, з одного місця — модуля, який день і
# тримає. Виводить те саме, що доти бачила жінка в рядку випадку (`%g`), тож
# шапка показу не міняється; змінюється те, що суть і «звідки» більше НЕ
# округлюють нишком і не можуть розійтися з рядком випадку.
def темп_словами(темп_c):
    """Температура дня для ЛЮДСЬКОГО тексту — один формат на всю систему.
    `None` → None. Читачі: рядок випадку й шапка показу (`паспорт_нагоди`), день
    фактами, «звідки» солі (нижче) і суть K-WEA-05 (`аксесуари_погода`)."""
    if темп_c in (None, ""):
        return None
    return "%g °C" % float(темп_c)


def сіль_на_дорозі(реагенти=None, темп_c=None, опади=None):
    """(чи є сіль на дорозі, звідки це відомо). Ручне слово `реагенти` («1»/«так»/«є» чи
    «0»/«ні»/«нема») сильніше за вивід; без нього — сніг чи мокрий сніг при ≤ `СІЛЬ_ДО_C`."""
    if реагенти not in (None, ""):
        с = str(реагенти).strip().lower()
        so = с not in ("0", "0.0", "ні", "нема", "немає", "false", "no")
        return so, ("реагенти оголошені рукою: %s" % ("є" if so else "нема"))
    о = канон_опади(опади, темп_c)
    if о in СОЛЬОВІ_ОПАДИ and темп_c is not None and float(темп_c) <= СІЛЬ_ДО_C:
        return True, ("виведено з погоди: «%s» при %s — смуга солі K-WEA-07" % (о, темп_словами(темп_c)))
    return False, None


