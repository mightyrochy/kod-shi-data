def частина_доби(г):
    """Код частини доби (`внутрішня_мова` part_of_day) для години 0–23."""
    return "morning" if 5 <= г < 11 else "day" if 11 <= г < 17 else "evening" if 17 <= г < 22 else "night"


def день_кодами(сцен):
    """dict її дня внутрішньою мовою — коди й числа, лише відоме.

    Вхід — сценарій після `з_показу` (там уже дія й поверхня зі слів). Порожній dict —
    сценарій про день не знає нічого. Схема — `протокол.ДЕНЬ`.

    ЗАМОВЧУВАННЯ ФОРМИ — НЕ ФАКТ ЇЇ ДНЯ (В-2). 11:00 і +18 °C, яких рука не торкалась і
    яких вона не називала (`типові_поля` показу; поле з її слів показ із цього переліку знімає), правила
    читають, як доти, — але в «день» для моделей вони не йдуть, як і в `case`
    (`пакет_моделі.випадок_для_пакета`). Доти рука 1 діставала в `day` `temperature_c: 18, start_hour:
    11, part_of_day: day, light: daylight` — погоду й годину, яких жінка не казала, фактами її дня.
    Разом із годиною не йде й те, що з неї виведено (частина доби, світло, «до ночі»), а з
    температурою — сіль на дорогах.

    ТИПОВЕ-1: замовчування знімає вже `з_показу` (поле лишається, лише коли паспорт почув його від
    неї — тоді воно її, хоч плитки рука й не торкалась). Тут те, чого вона не назвала, їде фактом
    «невідомо»: `unknown` — ключі дня, які форма стояла типовими й ніхто не назвав."""
    с = dict(сцен or {})
    типові = {str(x) for x in (с.get("типові_поля") or ())}
    невідоме = [ключ for ім, ключ in (("місце", "place"), ("година", "start_hour"), ("темп_c", "temperature_c"))
                if ім in типові and с.get(ім) in (None, "")]
    число = lambda v: int(v) if float(v).is_integer() else float(v)
    д = {}
    for ключ, поле, ім in _КОДИ_ДНЯ:
        к = _ВМ.код(поле, с.get(ім)) if с.get(ім) not in (None, "", "невідомо") else None
        if к:
            д[ключ] = к
    if с.get("тривалість_год") not in (None, ""):
        д["duration_h"] = число(с["тривалість_год"])
    # число з відчуття — для правил (`темп_для_правил`); моделі її день несе відчуттям, не вигаданими градусами
    if с.get("темп_c") not in (None, "") and not с.get("темп_з_відчуття"):
        д["temperature_c"] = число(с["темп_c"])
    if с.get("погода_відчуття") not in (None, ""):
        д["weather_feel"] = с["погода_відчуття"]
    if _ВМ.код("season", с.get("пора_року")):
        д["season"] = _ВМ.код("season", с["пора_року"])
    опади = _ВМ.код("precipitation", канон_опади(с.get("опади"))) if с.get("опади") not in (None, "") else None
    if опади:
        д["precipitation"] = опади
    try:
        if с.get("вітер") not in (None, "") and float(с["вітер"]) >= ВІТЕР_ПОМІТНИЙ:
            д["wind_ms"] = число(с["вітер"])
    except (TypeError, ValueError):
        д["wind"] = {"free_text": str(с["вітер"]), "lang": "uk"}     # слово замість числа — переказ
    if с.get("сонце"):
        д["direct_sun"] = True
    if сіль_на_дорозі(с.get("реагенти"), с.get("темп_c"), с.get("опади"))[0]:
        д["road_salt"] = True
    if с.get("година") not in (None, ""):
        г = int(float(с["година"])) % 24
        кінець = (г + float(с["тривалість_год"])) if с.get("тривалість_год") not in (None, "") else None
        # година пори — число коду: моделям — лише пора кодом
        д.update(part_of_day=_ВМ.код("part_of_day", с.get("пора")) or частина_доби(г)) if с.get("година_з_пори") \
            else д.update(start_hour=г, part_of_day=частина_доби(г))
        if кінець is not None and кінець >= 22:
            д["until_night"] = True
        світло = ("artificial" if (г >= 20 or г < 6 or (кінець or 0) >= 21)
                  else "daylight" if 7 <= г < 17 else None)
        if світло:
            д["light"] = світло
    _о = с.get("_ошатність") or с.get("ошатність")
    if isinstance(_о, (list, tuple)) and len(_о) == 2:
        д["formality"] = {"from": число(_о[0]), "to": число(_о[1])}
    from occasion import потреба_події, виміри_на_дріт
    if с:
        д["occasion_requirements"] = виміри_на_дріт(потреба_події(с))
    if невідоме:
        д["unknown"] = невідоме
    return д
