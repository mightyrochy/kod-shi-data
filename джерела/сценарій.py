# Невідоме не вигадується: чого сценарій не знає, того ключа нема.
ДІЯ_СЛОВАМИ = {"прогулянка": "прогулянка просто неба", "ходьба": "багато ходити пішки",
               "діти": "з дітьми", "нерівний_ґрунт": "стежки й нерівний ґрунт"}
ФОРМАТ_СЛОВАМИ = {"просто неба": "просто неба", "приміщення": "у приміщенні",
                  "змішано": "і в приміщенні, і надворі"}
ОПАДИ_СЛОВАМИ = {ОПАДИ_НІ: "без опадів", "дощ": "дощ", "злива": "злива",
                 "мокрий_сніг": "мокрий сніг", "сніг": "сніг"}
ВІТЕР_ПОМІТНИЙ = 6.0     # м/с — той самий поріг, що тримає верхній шар у `композитор_збирання`


def _частина_доби(г):
    """Слово для години доби 0–23: ранок, день, вечір або ніч."""
    return "ранок" if 5 <= г < 11 else "день" if 11 <= г < 17 else "вечір" if 17 <= г < 22 else "ніч"


def день_словами(сцен):
    """dict її дня словами (дія, де, скільки, погода, світло, рівень) — лише відоме.

    Вхід — сценарій після `з_показу` (там уже дія й поверхня зі слів). Значення — короткі
    фрази для моделі: факти, не поради. Порожній dict — сценарій про день не знає нічого."""
    с = dict(сцен or {})
    д = {}
    дія = [ДІЯ_СЛОВАМИ.get(с.get("активність")), с.get("рух") if с.get("рух") not in (None, "невідомо") else None]
    if any(дія):
        д["дія"] = "; ".join(x for x in дія if x)
    де = [str(с.get("місце") or "").replace("_", " ").strip() or None, ФОРМАТ_СЛОВАМИ.get(с.get("формат")),
          ("під ногами — %s" % с["поверхня"]) if с.get("поверхня") else None]
    if any(де):
        д["де"] = ", ".join(x for x in де if x)
    if с.get("тривалість_год") not in (None, ""):
        д["скільки"] = "близько %g год" % float(с["тривалість_год"])
    пог = []
    if с.get("темп_c") not in (None, ""):
        пог.append(темп_словами(с["темп_c"]))
    if канон_опади(с.get("опади")) in ОПАДИ_СЛОВАМИ:
        пог.append(ОПАДИ_СЛОВАМИ[канон_опади(с.get("опади"))])
    try:
        if с.get("вітер") not in (None, "") and float(с["вітер"]) >= ВІТЕР_ПОМІТНИЙ:
            пог.append("вітер %g м/с" % float(с["вітер"]))
    except (TypeError, ValueError):
        пог.append("вітер: %s" % с["вітер"])        # слово замість числа — переказ, не вигадка
    if с.get("сонце"):
        пог.append("пряме сонце")
    if сіль_на_дорозі(с.get("реагенти"), с.get("темп_c"), с.get("опади"))[0]:
        пог.append("на дорогах сіль і реагенти")
    if пог:
        д["погода"] = ", ".join(пог)
    if с.get("година") not in (None, ""):
        г = int(float(с["година"])) % 24
        кінець = (г + float(с["тривалість_год"])) if с.get("тривалість_год") not in (None, "") else None
        д["світло"] = ("з %02d:00 — %s" % (г, _частина_доби(г))
                       + (" і до ночі" if кінець is not None and кінець >= 22 else "")
                       + ("; надворі темно, світло штучне" if (г >= 20 or г < 6 or (кінець or 0) >= 21)
                          else "; денне світло" if 7 <= г < 17 else ""))
    рів = []
    _о = с.get("_ошатність") or с.get("ошатність")
    if isinstance(_о, (list, tuple)) and len(_о) == 2:
        рів.append("ошатність %g–%g із 10 (1 — дім, 5 — офіс, 9 — урочистість)" % (float(_о[0]), float(_о[1])))
    if с.get("дрес_код"):
        рів.append("дрес-код %s" % str(с["дрес_код"]).replace("_", " "))
    if рів:
        д["рівень"] = "; ".join(рів)
    return д
