# -*- coding: utf-8 -*-
"""ПОКРОКОВИК — генератор, що поступається головному потоку сторінки: доведення до кінця (`ганяти`),
збирач сміття на час побудови (`без_збирача`) і мить поступки (`пора`).

ЧОМУ ОКРЕМИЙ МОДУЛЬ (наряд 3.3, К-4). Ці три засоби кличуть покроковики фіду, фото, кадрів, каталогу,
пакета й композитора; доти вони жили в `фід_розбір`, і `фід_фото` діставав їх лінивим імпортом у
тілі функції, бо `фід_розбір` сам імпортує `фід_фото`, — цикл у графі імпортів. Тут вони нижче за
всіх, хто їх кличе; `фід_розбір` реекспортує ті самі об'єкти (стан `_остання_поступка` — один).
Код перенесено дослівно.

РЕБРА. Імпортує лише стандартні `gc` і `time`."""
import gc as _gc


def ганяти(г):
    """Доводить генератор-покроковик до кінця: `yield` у ньому — лише місце, де виконавець може поступитися головному
    потоку сторінки (`оцінка_образу.прогріти_каталог_без_блоку`); значення `return` — результат."""
    try:
        while True:
            next(г)
    except StopIteration as к:
        return к.value


def без_збирача(г):
    """Покроковик `г`, поки він будує велику купу нових контейнерів без циклів (розбір фіду, відновлення бази): збирач
    сміття вимкнено — повні збирання по купі, що росте, з'їдали третину-половину часу (CPython: розбір фіду 3,1 → 2,2 с,
    відновлення бази 0,9 → 0,5 с). Між поступками побудоване йде в «вічне» покоління (`gc.freeze`: збирач його більше не
    обходить, звільняє його лічильник посилань, як і раніше) і збирач вмикається назад — сторінка живе за своїми правилами.
    Наприкінці `gc.unfreeze()`: заморожене не лишається поза збирачем назавжди (циклічне сміття сторінки, що потрапило в
    купу на мить заморозки, інакше ніколи б не збиралося); обхід купи наприкінці коштує як повне збирання (≈ 0,1 с
    CPython), а виграш зберігається: 2,9 с проти 3,6 с без правки на `база_кроками`."""
    було = _gc.isenabled()
    _gc.disable()
    try:
        while True:
            try:
                к = next(г)
            except StopIteration as е:
                return е.value
            _gc.freeze()
            if було:
                _gc.enable()
            yield к
            if було:
                _gc.disable()
    finally:
        _gc.unfreeze()
        if було:
            _gc.enable()


_ПОСТУПКА_С = 0.12          # скільки секунд покроковик працює поспіль, перш ніж поступитися головному потоку


_остання_поступка = [0.0]


def пора():
    """Чи час поступитися: від попередньої поступки минуло `_ПОСТУПКА_С`. Цикли покроковиків питають це на кожному
    витку й роблять `yield` лише тоді — шматок тримається ≈ 0,12 с на будь-якому залізі, а поступок не більше,
    ніж потрібно (кожна — окремий хід події сторінки)."""
    import time
    т = time.perf_counter()
    if т - _остання_поступка[0] < _ПОСТУПКА_С:
        return False
    _остання_поступка[0] = т
    return True
