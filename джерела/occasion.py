import внутрішня_мова as _ВМ


# Вечір міняє світло, а не щабель. Вечір — частина дня від мовної моделі (`пора`), а не поріг години: її
# годину частиною дня робить модель (межа вечора — після 18:00, Emily Post, тема-5 §1.1; корінь Е2-частина-дня).
# Гучність C*·L*/50: рекомендовані весільними джерелами бордо/вино/теракота
# дають 23–32 (C*27–42, L*15–45), проблемні червоний/фуксія/кобальт/гірчиця
# — 62–87 (C*64–86). Стеля 45 розділяє їх із запасом; це калібрування
# вечірніх фото. Денних джерел немає: стеля лишається None.
# Родовід: українські весільні джерела Cosmo.ua (біле на фотографіях),
# bigmir (приглушити червоне); ukr.net/uainfo/tsn/radiotrek — один передрук.
# Траур: шість незалежних українських джерел, K-COL-03/K-OCC-01:
# темні відтінки без яскравих деталей, блиск обмежено біля обличчя.
РЕЄСТР = {
    "вечірня_гучність": dict(t="T3", val=45.0, прав=["K-KOH-08"], джерело="wedding_evening_photos"),
    "смуги": dict(t="T3", val=dict(тихі=(23.0, 32.0), гучні=(62.0, 87.0),
                                     хрома_гучних=(64.0, 86.0), L_темних=(15.0, 45.0)),
                  прав=["K-KOH-08"], джерело="wedding_evening_photos"),
    "траур": dict(t="T3", val=dict(L_макс=45.0, стеля_хроми=18.0,
                                    блиск_від=2, оздоба_від=3,
                                    оздоблені_візерунки=("квітковий", "вишивка")),
                  прав=["K-OCC-01", "K-COL-03"], джерело="mourning_dark_quiet_near_face"),
    "ділова": dict(t="T3", val=dict(L_вікно=(20.0, 80.0), стеля_хроми=40.0),
                   прав=["K-COL-03"], джерело="business_convention"),
}
ДРЕС_КОДИ_БЕЗ_БІЛОГО = ("all_black", "black_and_white")
ВЕЧІРНІ_ПОРИ = ("вечір", "ніч")          # ключі `part_of_day` (`внутрішня_мова`), що несуть вечірнє світло
ГУЧНІ_ВІЗЕРУНКИ = ("горох", "анімалістичний", "квітковий", "принт", "абстрактний",
                    "геометричний", "камуфляж")


def ключ_пори(пора):
    """Ключ частини дня (`ранок`, `день`, `вечір`, `ніч`) з ключа чи коду `part_of_day`; інакше None."""
    if not isinstance(пора, str) or not пора:
        return None
    return пора if _ВМ.код("part_of_day", пора) else _ВМ.ключ("part_of_day", пора)


def вечірня_пора(пора):
    """Чи частина дня (`пора`: ключ чи код `part_of_day`) несе вечірнє світло, без зміни ошатності."""
    return ключ_пори(пора) in ВЕЧІРНІ_ПОРИ


def потреба_події(сценарій=None, паспорт=None, *, траур=None):
    """Один опис вимірів події з полів паспорта; None — невідоме обмеження.

    Траур понад щабель; біле зарезервовано роллю, а вечірню стелю дає
    світло. Явний стан трауру можна передати читачеві вже обчисленим.
    Лінивий імпорт розриває коло з читачем траурного регістру.
    """
    с = dict(сценарій or {})
    с.update({к: v for к, v in (паспорт or {}).items()
              if к in ПОЛЯ_ПАСПОРТА and v not in (None, "")})
    if траур is None:
        import траурний_регістр as т
        тр = т.траур_сцени(с)
        траур = bool(тр and тр.get("лишилось"))
    пора = ключ_пори(с.get("пора"))
    світло = "evening" if вечірня_пора(пора) else "daylight" if пора else "unknown"
    дрес = str(с.get("дрес_код") or "").strip().lower().replace("-", "_").replace(" ", "_")
    п = dict(код=None, світло=світло, траур=bool(траур), вето_майже_біле=False,
             L_вікно=None, L_макс=None, стеля_хроми=None, стеля_гучності=None,
             джерело_гучності="unknown", гучність_смуги=None,
             блиск_від=None, оздоба_від=None, візерунки=(), оздоблені_візерунки=())
    if траур:
        п.update(РЕЄСТР["траур"]["val"], код="mourning", візерунки=ГУЧНІ_ВІЗЕРУНКИ)
        п.update(стеля_гучності=п["стеля_хроми"] * п["L_макс"] / 50.0,
                 джерело_гучності="mourning_dark_quiet_near_face")
    elif с.get("зарезервований_колір") == "near_white":
        п.update(код="reserved_white", вето_майже_біле=дрес not in ДРЕС_КОДИ_БЕЗ_БІЛОГО)
        if світло == "evening":
            п.update(стеля_гучності=РЕЄСТР["вечірня_гучність"]["val"],
                     джерело_гучності=РЕЄСТР["вечірня_гучність"]["джерело"],
                     гучність_смуги=РЕЄСТР["смуги"]["val"])
    elif дрес in ДРЕС_КОДИ_ДІЛОВІ:
        п.update(РЕЄСТР["ділова"]["val"], код="business")
    return п


def виміри_на_дріт(потреба):
    """Проєкція того самого опису кодами для моделі, без текстів і нових порогів."""
    п = потреба
    return dict(profile=п["код"] or "unknown", light=п["світло"], mourning=п["траур"],
                lightness_range=п["L_вікно"], lightness_max=п["L_макс"],
                chroma_max=п["стеля_хроми"], loudness_max=п["стеля_гучності"],
                loudness_source=п["джерело_гучності"], near_white_veto=п["вето_майже_біле"],
                shine_near_face_from=п["блиск_від"], festive_trim_shine_from=п["оздоба_від"],
                decorated_headwear_or_nonmetal_jewelry=[_ВМ.код_або_невідомо("pattern", к)
                                                       for к in п["оздоблені_візерунки"]],
                loud_patterns_large_or_near_face=[_ВМ.код_або_невідомо("pattern", к) for к in п["візерунки"]])
