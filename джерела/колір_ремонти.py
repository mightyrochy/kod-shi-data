"""ПЛОЩОЗАЛЕЖНІ ПРАВИЛА Й СУМІСНІСТЬ РЕМОНТІВ: реєстр правил, які без виміряних
площ не виносяться, знахідка «площа», якою вони себе називають, і пояснення
перетину колірних цілей — K-COL-CONF (конфлікт на одному носії) та K-COL-JOIN
(спільне вікно без пропозиції заміни).

ЩО ТУТ (перенесено з `колір_образу.py` без зміни жодного рядка коду, хвиля
СТАНДАРТ_КОДУ п.16; рядки — за `колір_образу.py` до поділу):
  · ПЛОЩОЗАЛЕЖНІ, ПЛОЩОЗАЛЕЖНІ_ІД, `_утримано_без_площ` (1226–1253);
  · РЕЖИМ_ОСІ, `_ОСІ_ЗАПИТУ` (1255–1277) — вимога чи альтернатива на осі запиту;
  · `_спільні_вікна`, `несумісні_ремонти` (1279–1428).

Читає лише `ід_правил` і `реєстр_правил`; жодного `колір_*` і фасад
`колір_образу` не імпортує.
"""
import внутрішня_мова as _ВМ
import ід_правил as ІП
from реєстр_правил import зн as _зн

ПЛОЩОЗАЛЕЖНІ = ["K-COL-01 (структура світлоти)", "K-COL-02 (бюджет і конфлікт хром)",
                "K-COMP-03 (кількість сімей)", "K-COL-05 (сирота-акцент і matchy)",
                "K-COL-06 (крос-нейтралі)"]
# ID того самого реєстру, витягнуті одним шаблоном проєкту (`ід_правил`), а не другим
# ручним списком: інакше список і його ID розійшлись би на першій же правці.
ПЛОЩОЗАЛЕЖНІ_ІД = tuple(ІП.усі_в_тексті(" ".join(ПЛОЩОЗАЛЕЖНІ)))

def утримано_без_площ(E):
    """Сила ≤ верифікація, застосована до ПЛОЩІ. Без виміряних площ ці правила не
    пом'якшуються і не вгадуються — вони не виносяться взагалі. Раніше на їх місці
    мовчки працювала таблиця слотів, і вердикт виглядав однаково впевнено."""
    нема = sorted({e["річ"] for e in E if e["площа"] is None})
    # ── «УТРИМАНО» НЕСЕ ЧИСЛО, А НЕ ЛИШЕ ФАКТ (Н-outfit-1-081) ──────────────
    # Свідком виміру є ПОХОДЖЕННЯ площі (`джерело_площі`), а не наявність числа в
    # полі. Доти знахідка казала «площі не виміряні» і не казала СКІЛЬКИ: 0 % і 80 %
    # виглядали однаково, тож рух покриття вгору не був видний ніде — ні в знімку, ні
    # у вердикті. Тепер частка речей із названим походженням площі стоїть у знахідці,
    # і саме її міряє прилад `gate_площі.py`.
    речей = {e["річ"] for e in E}
    з_джерелом = {e["річ"] for e in E if e.get("джерело_площі")}
    return dict(правило="площа", сила="утримано",
                сила_нп=None, сила_нп_джерело="виміру нема (утримано): площі не виміряні",
        суть=_ВМ.суть_кодом([_ВМ.заява("areas_not_measured")], нема),
        заяви=[_ВМ.заява("areas_not_measured")],
        речі=нема, чому="площа речі не подана; таблиці слотів у модулі більше нема",
        покриття_входу=(round(len(з_джерелом) / len(речей), 3) if речей else None),
        утримані_правила=ПЛОЩОЗАЛЕЖНІ,
        ремонт="подати маски образу (areas.образ_з_масок) або довжини виробів на цьому "
               "тілі (areas.образ_з_геометрії) — обидва дають площу з реальних чисел")

# ── РЕЖИМ ОСІ ЗАПИТУ: вимога чи одна з альтернатив (Н-outfit-2-092) ──────────
# Принцип: `_ОСІ_ЗАПИТУ` клала «цільова_L», «цільова_L_темніше» і
# «цільова_L_світліше» на ОДНУ вісь "L", а `несумісні_ремонти` будувала з неї
# словник {вісь: вікно}. Ключ у словнику один — тож із двох альтернатив правила
# доживала РІВНО ОДНА, та, що стояла в запиті останньою; половина вікна зникала
# мовчки. Правило, яке віддало вибір «темніше АБО світліше», виглядало далі як
# правило з єдиною вимогою, і на перетині з чужим вікном народжувався K-COL-CONF
# там, де конфлікту нема: друга альтернатива перетиналась, але її вже не було.
# Режим — не прикраса словника, а те, ЧИМ вікно є для правила: вимогу не можна
# не виконати, альтернативу можна замінити сестрою.
РЕЖИМ_ОСІ = {
 "вимога":       dict(альтернатива=False,
                      чому="правило просить рівно це вікно; іншого вікна цієї осі "
                           "від того самого правила нема, і замінити його нічим"),
 "альтернатива": dict(альтернатива=True,
                      чому="правило віддало кілька вікон НА ВИБІР (темніше АБО "
                           "світліше) — виконання будь-якого задовольняє правило, "
                           "тому перетин порожній лише тоді, коли не перетнулась ЖОДНА"),
}
ОСІ_ЗАПИТУ = {"цільова_L": ("L", "вимога"),
               "цільова_L_темніше": ("L", "альтернатива"),
               "цільова_L_світліше": ("L", "альтернатива"),
               "цільове_b": ("b", "вимога"), "цільова_C": ("C", "вимога")}

def спільні_вікна(вікна_правил):
    """Усі непорожні спільні вікна ОДНІЄЇ осі: по одному вікну від КОЖНОГО правила.

    Правило з альтернативами («темніше АБО світліше») дає кілька вікон, і досить,
    щоб перетнулась ОДНА — тому тут не одне вікно, а список живих перетинів, кожен
    із назвою зробленого вибору. Порожній список означає справжній конфлікт: не
    перетнулась ЖОДНА комбінація.

    Комбінаторного вибуху нема: перетини дедуплікуються за власними межами, а
    альтернативи того самого правила або вкладені, або рознесені, тож після кожного
    правила живих лишаються одиниці, а не добуток.

    Повертає [(вікно, вибір)], де `вибір` — кортеж (правило, узяте_вікно, усі_вікна)
    лише для тих правил, які справді мали з чого вибирати."""
    живі = [(None, ())]
    for правило, вікна in вікна_правил:
        нові = {}
        for w, вибір in живі:
            for lo, hi in вікна:
                a, b = (lo, hi) if w is None else (max(w[0], lo), min(w[1], hi))
                if a > b: continue
                мітка = вибір + (((правило, (lo, hi), tuple(вікна)),) if len(вікна) > 1 else ())
                нові.setdefault((a, b), ((a, b), мітка))
        живі = list(нові.values())
        if not живі: return []
    return живі

def несумісні_ремонти(зн):
    """Пояснює сумісність колірних цілей, не видаючи їх за перевірений ремонт.

    Перетин вікон — лише арифметика цілей правил. Він не доводить, що річ
    із цього перетину пройде повний суд. Кандидатів добору перевіряє
    `пропозиція_заміни`, коли викликач має склад, межі запиту й явний вибір.
    """
    по_носіях = {}
    for z in зн:
        q = z.get("запит_у_каталог") or {}
        вимоги, альтернативи = {}, {}
        for k, v in q.items():
            if k not in ОСІ_ЗАПИТУ: continue
            if not (isinstance(v, (list, tuple)) and len(v) == 2): continue
            вісь, режим = ОСІ_ЗАПИТУ[k]
            куди = альтернативи if РЕЖИМ_ОСІ[режим]["альтернатива"] else вимоги
            куди.setdefault(вісь, []).append((float(v[0]), float(v[1])))
        # ВИМОГА ПЕРЕБИВАЄ АЛЬТЕРНАТИВИ ТОГО САМОГО ПРАВИЛА НА ТІЙ САМІЙ ОСІ, і це
        # свідомо: вимога — не вибір, тому «перетяти її з альтернативами» означало б
        # вигадати тут правило узгодження, якого жоден емітент у дереві не просить
        # (жоден не пише на одну вісь і вимогу, і альтернативу). Кілька вимог від
        # одного правила — це вже перетин, не вибір.
        осі = {}
        for вісь, вікна in вимоги.items():
            осі[вісь] = [(max(w[0] for w in вікна), min(w[1] for w in вікна))]
        for вісь, вікна in альтернативи.items():
            осі.setdefault(вісь, list(вікна))
        if not осі: continue
        for частина in str(q.get("слот") or "").replace(",", "|").split("|"):
            сл = частина.strip()
            if сл: по_носіях.setdefault(сл, []).append((z.get("правило"), осі))
    out = []
    for носій, група in sorted(по_носіях.items()):
        if len(група) < 2: continue
        обм, правила = {}, sorted({п for п, _ in група})
        порожні, вибори = {}, []
        for вісь in sorted({в for _, осі in група for в in осі}):
            вікна_правил = [(п, осі[вісь]) for п, осі in група if вісь in осі]
            живі = спільні_вікна(вікна_правил)
            просять = " ∩ ".join("%s %s" % (п, " або ".join(str(w) for w in ww))
                                 for п, ww in вікна_правил)
            if not живі:
                # РЯДОК КАЖЕ, ЩО САМЕ НЕ ЗІЙШЛОСЬ. Коли в грі були альтернативи,
                # «разом виходить (47.0, 45.0)» було б брехнею: перетиналась не одна
                # пара меж, а жодна КОМБІНАЦІЯ вибору — і саме це тепер написано.
                порожні[вісь] = dict(просять=просять, разом=(
                    "жодна комбінація альтернатив не перетинається"
                    if any(len(ww) > 1 for _, ww in вікна_правил) else
                    str((max(w[0] for _, ww in вікна_правил for w in ww),
                         min(w[1] for _, ww in вікна_правил for w in ww)))))
                continue
            # НАЙШИРШИЙ ЖИВИЙ ПЕРЕТИН, а не перший-ліпший: вужче вікно відсікло б
            # каталог без підстави — обидві альтернативи правило віддало рівноцінними.
            w, мітка = max(живі, key=lambda x: x[0][1] - x[0][0])
            обм[вісь] = w
            for правило, взяте, усі in мітка:
                вибори.append("%s на осі %s: з %s узято %s (перетин найширший)"
                              % (правило, вісь, " або ".join(str(x) for x in усі), взяте))
        if порожні:
            деталі = "; ".join("%s: %s, разом виходить %s" % (в, d["просять"], d["разом"])
                               for в, d in порожні.items())
            out.append(_зн("K-COL-CONF", "soft",
                "«%s»: %s мають несумісні цілі за %s"
                % (носій, " і ".join(правила), "/".join(sorted(порожні))), [носій],
                "носій «%s»: %s" % (носій, деталі),
                заяви=[_ВМ.заява("two_fixes_pull_one_item_apart", slot=_ВМ.код_або_невідомо("slot", носій),
                                 axes=[{"L": "lightness", "C": "chroma", "h": "hue"}.get(в, в) for в in sorted(порожні)])],
                ламається="конфлікт цілей, не помилка: приобличчевий контраст (R-CHEV-06 — "
                          "фізика) і читаність кроку між нейтралями (T3 ремесло) на "
                          "низькоконтрастній особі тягнуть у різні боки; порядок пріоритету "
                          "доказом НЕ встановлений, тому знахідка лише пояснює конфлікт"))
        elif len(правила) >= 2:
            # Сила, регістр і вага — з конструктора: вагу 0.0 дає корпус (`ВАГА_НУЛЬ_ЗА_КОРПУСОМ`).
            out.append(_зн("K-COL-JOIN", "hint",
                "кілька ремонтів на одному носії — спільне вікно", [носій],
                ("перетин вікон %s правил %s" % (обм, правила)
                 + ("; вибір з альтернатив — " + "; ".join(вибори) if вибори else "")),
                заяви=[_ВМ.заява("several_colour_fixes_one_item", slot=_ВМ.код_або_невідомо("slot", носій))]))
    return out
