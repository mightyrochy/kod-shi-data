def займають_одне(слот_а, слот_б):
    """Чи дві речі не стоять в одному образі разом: той самий слот, або слот однієї — серед
    місць, які займає інша (`річ_з_фото.займає`: сукня займає верх і низ).

    ЧОМУ НЕ ПЕРЕТИН `займає(а) & займає(б)`. Верх займає {верх, сукня, комплект}, низ — {низ,
    сукня, комплект}: перетин непорожній, і верх із низом виходили б однією річчю на одне місце,
    хоч образ «верх + низ» — звичайний. Сукня з верхом справді не стоять: «верх» ∈ займає(сукня)."""
    if not слот_а or not слот_б:
        return False
    return слот_а == слот_б or слот_а in _РФ.займає(слот_б) or слот_б in _РФ.займає(слот_а)


def скласти(речі):
    """Речі з фото → (образ, запасні, конфлікти) ідами.

    Образ — речі «in_outfit» по одній на місце в структурі (`займають_одне`). Друга річ на те
    саме місце — не друга сукня в образі, а її запасна: код пробує її як зміну. Хто переміг,
    названо в `конфлікти` (перша за порядком фото — бо так вона їх показала). Річ без слота в
    образ не стає: їй нема місця, і це сказано."""
    образ, запасні, конфлікти, слоти = [], [], [], {}
    for р in речі or []:
        сл = р.get("слот")
        if not сл:
            конфлікти.append(dict(річ=р["ід"], чому="no_slot"))
            continue
        if not р.get("в_образі", True):
            запасні.append(р["ід"])
            continue
        хто = sorted(і for і, с in слоти.items() if займають_одне(сл, с))
        if хто:
            запасні.append(р["ід"])
            конфлікти.append(dict(річ=р["ід"], чому="same_place", з=хто))
            continue
        образ.append(р["ід"])
        слоти[р["ід"]] = сл
    return образ, запасні, конфлікти


