    return ("Your verdict \"wear_as_is\" contradicts the check: blocking findings %s%s. Answer again "
            "with the same schema." % (", ".join(str(х) for х in гейти) or "—",
                                       ("; structure blockers " + ", ".join(str(х) for х in блок)) if блок else ""))
