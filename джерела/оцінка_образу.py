def сценарій_оцінки(екран, слова=None):
    """Нагода й погода, які ВОНА назвала → (сценарій ядра, звідки кожне поле).

    Екран сильніший за слова: поле, заповнене рукою, словами не переписується. Зі слів — лише
    коди таблиці й число градусів; «холодно» числом не стає (таблиця відчуттів дає середину
    смуги, а це вже здогад). Порожнього тут нема: чого вона не назвала, того в сцені нема."""
    сц, звідки = {}, {}
    for к, v in (екран or {}).items():
        if v not in (None, ""):
            сц[к], звідки[к] = v, "screen"
    с = слова if isinstance(слова, dict) else {}
    for код_поля, ключ_ядра in _ЗІ_СЛІВ:
        к = _ВМ.ключ(код_поля, с.get(код_поля))
        if к and ключ_ядра not in сц:
            сц[ключ_ядра], звідки[ключ_ядра] = к, "her_words"
    т = с.get("temperature_c")
    if "темп_c" not in сц and isinstance(т, (int, float)) and not isinstance(т, bool):
        сц["темп_c"], звідки["темп_c"] = float(т), "her_words"
    return сц, звідки


def прогріти_каталог(d):
    """Каталог піднімається, поки модель дивиться на фото (показ кличе цей крок одразу після
    виклику `РЕЧІ`): `feed.прогін` кешує себе сам, і крок «суд» бере вже теплий каталог."""
    if not d.get("каталог"):
        return dict(готово=False, чому="у збірці нема каталогу")
    F, T, dd = _профіль(d)
    сц, _звідки = сценарій_оцінки(d.get("сценарій_оцінки"), d.get("сценарій_слів"))
    сцен, _н = _сцена(сц, dd)
    try:
        _пули, чому, готовий, пак = _крамниця(dd, F, T, сцен, [])
    except (KeyError, TypeError, ValueError) as е:
        # П.14: чужий вхід (каталог не той, профіль без обхватів) — прогрів лише пришвидшує,
        # і його провал оцінки не зупиняє: крок «суд» назве ту саму причину своїм полем
        return dict(готово=False, чому="%s: %s" % (type(е).__name__, е))
    return dict(готово=bool(готовий), чому=чому, речей=len(пак.get("_каталог") or []))


def _сцена(сценарій, d):
    """Сцена суду — ЛИШЕ те, що вона назвала (екран або її слова), і намір; без типових полів."""
