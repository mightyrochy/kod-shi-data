def _крамниця_кроками(d, F, T, сцен, слоти):
    """Кандидати крамниці для слотів цілей — записи каталогу: речі пулу рук (коли нагоду названо;
    `пакет_моделі.записи_пулу`), інакше каталог цього слота. Повертає ({слот: [записи]}, чому, пак_готовий).

    Генератор (див. `_ганяти`): пакет каталогу йде шматками (`міст_пакет.пакет_каталогу_кроками`).

    БЕЗ СЦЕНАРІЮ ПУЛ НЕ ЗБИРАЄТЬСЯ (K-IO-01), і пакет із нього крамниці дає лише `_каталог`; специфікації вікон і
    покриття каталогу (≈ 3,7 с у Pyodide, проба 5770) тоді не читає ніхто. Той самий `_каталог` дає
    `_каталог_без_пулу_кроками`; проба `проби/прогрів_крамниці_6512.py` звіряє записи обох шляхів."""
    dd = dict(d, сценарій={к: v for к, v in сцен.items() if not str(к).startswith("_")
                           and к in ("нагода", "місце", "дрес_код", "темп_c", "опади", "пора")})
    dd.pop("паспорт", None)
    F2, T2, зріст, kw = _МВ.збірка(dd)
    п, гілка, _сх, _під = _МО.пакет_гілки(dd, F2, T2, зріст, kw, None, dd.get("намір") or "conventional")
    вх = _МП.входи_пакета(dd, F2, T2, None)
    схема = п["палітри"]["розвилка"][0 if гілка is None else гілка]["схема"]
    if (not _СЦ.є_сценарій(вх["сценарій"]) and not вх["вимоги"] and not вх["паспорт"]
            and (схема in _P.СХЕМИ or схема == _P.МИСМАТЧ)):
        кат = yield from _каталог_без_пулу_кроками(dd)
        return ({с: [r for r in кат if r.get("слот") == с] for с in слоти},
                _СЦ.БРАК_СЦЕНАРІЮ, False, dict(_каталог=кат))
    пак = yield from _МП.пакет_каталогу_кроками(dd, F2, T2, п, (0 if гілка is None else гілка),
                                                 за_замовчуванням=(гілка is None))
    if пак.get("готово") and пак.get("кандидати"):
        # речі пулу — записами каталогу, як і без пулу: рядок пулу — вид речі для моделі (рядок 11864)
        записи, поза = _ПМ.записи_пулу(пак, слоти)
        return записи, ("pool_ids_outside_catalog=%d" % поза if поза else None), True, пак
    кат = пак.get("_каталог") or []
    return ({с: [r for r in кат if r.get("слот") == с] for с in слоти},
            пак.get("чому") or "пулу нема", False, пак)


def зміни_кроками(d, F, T, сцен, речі, образ, запасні, о0, палітра, драп=None, крамниця=True):
    """Перевірені зміни: її запасна річ, потім річ крамниці на місце цілі; образ переважується
    тим самим судом, лишаються ті, що зменшують `сума_сил`. Повертає (зміни, звіт).

    Генератор: `yield` після кожної спроби переважування й після пошуку в каталозі (див. `_ганяти`)."""
    за_ід = {р["ід"]: р for р in речі}
    записи = {р["ід"]: _РФ.запис_каталогу(dict(р, закріплена=True)) for р in речі}
    зн0, _ = _знахідки(о0, за_ід)
    цілі = _цілі(зн0, речі, образ)
    звіт = dict(цілі=цілі, сума_до=о0.get("сума_сил"), спроби=[], крамниця=None)
    if not цілі:
        return [], звіт
    yield
    сума0 = float(о0.get("сума_сил") or 0.0)
    правила0 = _правила(о0)
    свої, крамні = [], []

    def _спроба(ціль, нова_ід, нова_слот, запис, звідки):
        ід = _заміна(образ, за_ід, ціль, нова_ід, нова_слот)
        кат = [записи[і] for і in ід if і in записи] + ([запис] if нова_ід not in записи else [])
        о1 = _СЧ.відсутнє_на_фото(_ваги_образу([з["id"] for з in кат], кат, F, T, сцен, драп), [],
                                  {з.get("слот") for з in кат})[0]
        сума1 = float(о1.get("сума_сил") or 0.0)
        знято = sorted(правила0 - _правила(о1))
        додано = sorted(_правила(о1) - правила0)
        спроба = dict(ціль=ціль, нова=нова_ід, звідки=звідки, сума=round(сума1, 3),
                      дельта=round(сума1 - сума0, 3), знято=знято, додано=додано)
        звіт["спроби"].append(спроба)
        return спроба if сума1 < сума0 else None

    for ціль in цілі:
        сл = за_ід[ціль]["слот"]
        for з in запасні:
            if займають_одне(за_ід[з]["слот"], сл):
                с = _спроба(ціль, з, за_ід[з]["слот"], записи[з], "own")
                yield
                if с:
                    свої.append(с)
    if крамниця:
        слоти = sorted({за_ід[ц]["слот"] for ц in цілі})
        yield _КРОК_КРАМНИЦЯ
        try:
            пули, чому, готовий, _пак = _крамниця(d, F, T, сцен, слоти)
        except (KeyError, TypeError, ValueError) as е:
            # П.14: каталог — чужий вхід (показ може бути зібраний без нього); оцінка
            # стоїть і без крамниці, а причина — у звіті, не мовчанням
            пули, чому, готовий = {}, "%s: %s" % (type(е).__name__, е), False
        yield
        звіт["крамниця"] = dict(пул_рук=готовий, чому=чому,
                                кандидатів={с: len(р) for с, р in пули.items()})
        члени = {}      # членство вікна кольору в палітрі: одне на вікно, а не на кожного кандидата
        for ціль in цілі:
            сл = за_ід[ціль]["слот"]
            кандидати = []
            for н, r in enumerate(пули.get(сл) or []):
                if н % ЧИСЛО_КАНДИДАТІВ_НА_КРОК == 0:
                    yield
                if _КР_ТИП.межі_кольору(r) is None or not r.get("id"):
                    continue
                # річ-слово — вікном, не центром: лише «так» усім вікном, сила — мінімум
                у, сила = _РФ.членство_вікна(r, палітра, члени)
                if у != "так":
                    continue
                кандидати.append((сила, r))
            кандидати.sort(key=lambda х: -х[0])
            for _с, r in кандидати[:КРАМНИЦЯ_НА_ЦІЛЬ]:
                с = _спроба(ціль, r["id"], r.get("слот") or сл, dict(r), "shop")
                yield
                if с:
                    # вид речі крамниці кодом: без нього модель писала «заміни штани на
                    # спідницю-плісе», а картка показувала штани — текст про один вид, річ іншого
                    с["вид"] = _ВМ.код("item_type", r.get("тип"))
                    крамні.append(с)
    свої.sort(key=lambda с: с["дельта"])
    крамні.sort(key=lambda с: с["дельта"])
    обрані, бачено = [], set()
    for с in свої + крамні:
        if (с["ціль"], с["нова"]) in бачено:
            continue
        бачено.add((с["ціль"], с["нова"]))
        обрані.append(с)
        if len(обрані) >= ЗМІН_МАКС:
            break
    for н, с in enumerate(обрані):
        с["ід"] = "з%d" % (н + 1)
    крамні_ід = [с["нова"] for с in обрані if с["звідки"] == "shop"]
    if крамні_ід:
        yield _КРОК_ВІТРИНА
        yield from _покажчики_вітрини_кроками(d)
        звіт["вітрина"] = вітрина(d, крамні_ід)
        for с in обрані:
            if с["звідки"] == "shop":
                с["річ"] = звіт["вітрина"].get(с["нова"]) or {}
    return обрані, звіт


