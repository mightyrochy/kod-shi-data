def промпт_речей(фото):
    """Промпт речей на фото оцінки рядком — спільна задача «речі з фото» (`річ_з_фото.фото_речей`) з полем
    «outfit»: фото — ід і розмір (самі зображення їдуть блоками, кожне під підписом `річ_з_фото.підписи_фото`)."""
    ф = [dict(id=str(х.get("ід")), width=х.get("ширина"), height=х.get("висота"))
         for х in (фото or []) if isinstance(х, dict) and х.get("ід")]
    return _json.dumps(_ЗП.зібрати(_РФ.фото_речей(), {"photos": ф, "outfit": True, "codes": _РФ.коди_полів()}),
                       ensure_ascii=False)


def _рамка_списком(v):
    """Рамка моделі {left, top, right, bottom} → [ліво, верх, право, низ]; інше — як є."""
    return [v.get(к) for к in ("left", "top", "right", "bottom")] if isinstance(v, dict) else v


def _рамка(v):
    """Рамка моделі {left, top, right, bottom} (або список) → рамка `річ_з_фото` чи None."""
    return _РФ.рамка_з_тисячних(_рамка_списком(v))


def _в_образі(о):
    """`in_outfit` речі моделі → True / False / None («unknown» чи null: кадр не показує, чи вона її
    вдягає). Без поля — True, як доти: модель, що не сказала «запасна», назвала річ образу."""
    if "in_outfit" not in о:
        return True
    v = о["in_outfit"]
    с = str(v).strip().lower()
    if v is False or с == "false":
        return False
    return None if v is None or с in ("unknown", "null", "none", "") else True


def речі_з_відповіді(відповідь, фото):
    """Відповідь задачі `РЕЧІ` → {речі, незнайомі, без_речей, причина}.

    Ід речі ставить КОД (той самий порядок, що в `річ_з_фото.речі_з_json`): «ф1» — перша річ
    на фото ф1, «ф1·2» — друга. Річ на фото, якого в цьому виклику не було, не береться;
    фото, на якому модель не назвала нічого, — у `без_речей`, а не мовчанням."""
    # кілька JSON-об'єктів — останній цілий, відкинуте кодами в `нотатки` (СКЛАДАННЯ-1200, `протокол.розбір_останній`)
    об, причина, нотатки = _СВ.СХЕМИ_ВІДПОВІДІ["РЕЧІ_ОЦІНКИ"].прочитати(відповідь)
    фото_ід = [str(х.get("ід")) for х in (фото or []) if isinstance(х, dict) and х.get("ід")]
    вих = dict(речі=[], незнайомі=[], без_речей=[], причина=None, нотатки=нотатки)
    if not isinstance(об, dict) or not isinstance(об.get("items"), list):
        вих["причина"] = причина or "відповідь без списку «items»"
        вих["без_речей"] = фото_ід
        return вих
    лічба, побачені = {}, {}
    без_фото = 0
    for н, о in enumerate(об["items"]):
        if not isinstance(о, dict):
            вих["незнайомі"].append("items[%d]: не обʼєкт" % н)
            continue
        ф = str(о.get("photo") or "").strip()
        if ф not in фото_ід:
            if len(фото_ід) == 1 and not ф:
                ф = фото_ід[0]           # одне фото — модель могла його не назвати
            else:
                без_фото += not ф
                вих["незнайомі"].append("items[%d]: фото «%s» у виклику не було" % (н, ф))
                continue
        де = "items[%d]" % н
        вид = str(о.get("kind") or "").strip()
        if вид and вид not in _ВМ.ТАБЛИЦЯ["item_type"]:
            if not _ВМ.невідомо(вид):
                вих["незнайомі"].append("%s.kind: код «%s» поза переліком" % (де, вид))
            вид = ""
        р = dict(фото=ф, вид=вид or None,
                 назва=(" ".join(str(о.get("name") or "").split())[:80] or None),
                 слот=_ключ("slot", о.get("slot"), вих["незнайомі"], де),
                 колір=_ключ("color", о.get("color"), вих["незнайомі"], де),
                 матеріал=_ключ("fabric", о.get("fabric"), вих["незнайомі"], де),
                 крій=_ключ("cut", о.get("cut"), вих["незнайомі"], де),
                 довжина=_ключ("length", о.get("length"), вих["незнайомі"], де),
                 принт=_ключ("pattern", о.get("pattern"), вих["незнайомі"], де),
                 ошатність=_БР.число_щабля(о.get("formality")),
                 чия="невідомо",
                 в_образі=_в_образі(о),
                 рамка=_рамка(о.get("frame")))
        вироджена = _РФ.рамка_виродилась(_рамка_списком(о.get("frame")), де)
        if вироджена:
            вих["нотатки"].append(вироджена)        # річ без рамки, як не названо
        # слот — з виду, коли вид у таблиці: розбіжність зі «slot» моделі — кодом у `нотатки`
        слот_виду = _ВМ.ключ("slot", _ВМ.СЛОТ_ТИПУ.get(вид)) if вид else None
        if слот_виду and слот_виду != р["слот"]:
            вих["нотатки"].append("%s: %s.slot=%s kind=%s" % (СЛОТ_З_ВИДУ, де, о.get("slot"), вид))
            р["слот"] = слот_виду
        # ТОЧНИЙ ДУБЛЬ: 6б `seed3_11` назвала ті самі 4 речі двічі (фото, коди, рамка) — 8 рядків, і `скласти`
        # давало 5 «запасних». Збігається все, крім назви (слів код не судить, п.12): друга лишається в `нотатки`.
        відбиток = tuple(р[к] for к in ("фото", "вид", "слот", "колір", "матеріал", "крій", "довжина", "принт",
                                         "ошатність", "в_образі")) + (_json.dumps(р["рамка"], sort_keys=True, default=str),)
        if відбиток in побачені:
            вих["нотатки"].append("%s: %s=%s" % (ДУБЛЬ_РЕЧІ, де, побачені[відбиток]))
            continue
        лічба[ф] = лічба.get(ф, 0) + 1
        р["ід"] = ф if лічба[ф] == 1 else "%s·%d" % (ф, лічба[ф])
        побачені[відбиток] = р["ід"]
        вих["речі"].append(р)
    вих["без_речей"] = [ф for ф in фото_ід if not лічба.get(ф)]
    # ЗАПАСНА БЕЗ РЕЧІ, ЯКІЙ ВОНА ЗАПАСНА: «false — річ, показана НАТОМІСТЬ іншої», а на її місці
    # (`займають_одне`) жодної речі образу нема — сказане не має опори. Приклад: повтор формату дав
    # `in_outfit: false` усім чотирьом речам, образ лишився порожнім (`no_item_with_slot`) і картки не було.
    # Така річ — «кадр не показує» (None, як «unknown»): перша на своєму місці стає в образ, друга на тому ж
    # місці лишається запасною (`скласти`), і модель оцінки бачить обидві у `worn_unknown`.
    без_опори = []
    for р in вих["речі"]:
        if р["в_образі"] is False and р["слот"] and not any(
                х is not р and х["в_образі"] is not False and займають_одне(х["слот"], р["слот"])
                for х in вих["речі"]):
            р["в_образі"] = None
            без_опори.append(р["ід"])
    if без_опори:
        вих["нотатки"].append("%s: %s" % (ЗАПАСНА_БЕЗ_ОПОРИ, ",".join(без_опори)))
    # Два фото, а модель назвала речі й не сказала, на якому, — це не «на кадрах нема речей»,
    # а вада форми відповіді. Причина кодом (п.12) вмикає повтор формату в показі; після нього — заява з `why`.
    if not вих["речі"] and без_фото and без_фото == len(об["items"]):
        вих["причина"] = ФОТО_НЕ_НАЗВАНО
    return вих


# ═══════════ 2б. ВИПРАВЛЕННЯ ПЕРЕЛІКУ ЇЇ РУКОЮ ═══════════════════════════
def _поля_дії(д, де, незнайомі, було=None):
    """Дія `{slot, kind, color, in_outfit, photo, frame}` (коди) → {поле речі: значення ядра}; хибний код — у `незнайомі`.

    Слот і вид однієї дії можуть розійтись (голос: «там не штани, а ботильйони» — слот `bottom` із переліку, вид
    ботильйонів). Слово про вид точніше за слот, а слот дають і дотик, і копія з переліку: коли вид НАЗВАНО НАНОВО (нова
    річ або вид відрізняється від `було` — речі, яку правлять), слот береться з виду, як у `речі_з_відповіді`
    (`слот_з_виду`); коли вид той самий, що був, — це копія з переліку, і слово про місце сильніше: вид знімається."""
    п = {}
    if "slot" in д:
        к = _ключ("slot", д["slot"], незнайомі, де)
        if к:
            п["слот"] = к
    if "kind" in д and not _ВМ.невідомо(д["kind"]):
        if str(д["kind"]) in _ВМ.ТАБЛИЦЯ["item_type"]:
            п["вид"] = str(д["kind"])
        else:
            незнайомі.append("%s.kind: код «%s» поза переліком" % (де, д["kind"]))
    if "color" in д:
        к = _ключ("color", д["color"], незнайомі, де)
        if к:
            п["колір"] = к
    if "in_outfit" in д:
        п["в_образі"] = _в_образі({"in_outfit": д["in_outfit"]})
    if д.get("photo") is not None:
        ф, рамка = str(д["photo"]), _рамка(д.get("frame"))
        if _ФОТО_ІД.fullmatch(ф) and рамка:
            п.update(фото=ф, рамка=рамка, дотик=True)
        else:
            незнайомі.append("%s: дотик по фото «%s» без рамки чи з хибним ід" % (де, ф))
    слот_виду = _ВМ.ключ("slot", _ВМ.СЛОТ_ТИПУ.get(п["вид"])) if п.get("вид") else None
    if слот_виду and "слот" not in п:
        п["слот"] = слот_виду
    elif слот_виду and слот_виду != п.get("слот"):
        вид_наново = було is None or п["вид"] != було.get("вид")
        незнайомі.append("%s: слот «%s» не з виду «%s» — %s" % (
            де, п.get("слот"), п["вид"], "слот узято з виду" if вид_наново else "вид той самий, що був, — вид відкинуто"))
        if вид_наново:
            п["слот"] = слот_виду
        else:
            del п["вид"]
    return п


def _місце_речі(річ, фото, рамка):
    """Переносить той самий екземпляр на фото й ділянку, скидає знання зі старої ділянки."""
    річ.update(фото=фото, рамка=рамка)
    for поле in ("вимір", "палітра"):
        річ.pop(поле, None)


def виправити_речі(речі, дії, лічильник=0):
    """Перелік речей + її дії → {речі, дії, незнайомі, лічильник}. Дії — кодами: `{op: remove|set|add, item, slot, kind,
    color, in_outfit, photo, frame}`; тією самою функцією йдуть дотики й голос.

    Ід дописаної речі `н<N>` бере лічильник ПЕРЕЛІКУ, а не max поточних +1: прибрала `н2` і дописала нову —
    нова `н3`, а не знову `н2`, бо в `етапи.підтвердження.дії` і в суді `н2` — це одна річ. `лічильник` — скільки
    `н…` уже видано (показ несе його між викликами); не менший за найбільший `н…` у переліку.

    `remove` прибирає річ; `set` міняє її поля (колір — її код: `колір_її`, свідок виміру в `суд`; слот не з виду знімає
    `вид`; `photo`+`frame` — її дотик по фото: вікно навколо нього міряється у `суд`); `add` дописує річ `н1…` (дріт
    `h1`), без фото й рамки, `джерело: her`. Змінена річ несе `виправлено: [поля]`. Незнайому річ чи код дія пропускає,
    і це в `незнайомі`; у `дії` — те, що справді змінилось: {op, ід, поле, було, стало}."""
    поточні = [dict(р) for р in речі or [] if isinstance(р, dict) and р.get("ід")]
    звіт, незнайомі = [], []
    видано = max([int(лічильник or 0)] + [int(м.group(1)) for х in поточні for м in [_НОВА_ІД.fullmatch(str(х["ід"]))] if м])

    def змінити(р, поля, оп):
        попередні = dict(р)
        if "фото" in поля:
            _місце_речі(р, поля["фото"], поля["рамка"])
        for поле, нове in поля.items():
            було = попередні.get(поле)
            if було == нове:
                continue
            р[поле] = нове
            if поле == "колір":
                р["колір_її"] = True
            if поле != "дотик":
                звіт.append(dict(op=оп, ід=р["ід"], поле=поле, було=було, стало=нове))
                р["виправлено"] = [*(р.get("виправлено") or []), *([] if поле in (р.get("виправлено") or []) else [поле])]
        # слот змінено, а вид лишився з іншого слота — вид знімається (він був про іншу річ)
        вид = р.get("вид")
        if вид and "вид" not in поля and р.get("слот") != _ВМ.ключ("slot", _ВМ.СЛОТ_ТИПУ.get(вид)):
            звіт.append(dict(op=оп, ід=р["ід"], поле="вид", було=вид, стало=None))
            р["вид"] = None

    for н, д in enumerate(дії or []):
        де = "дії[%d]" % н
        if not isinstance(д, dict) or д.get("op") not in ДІЇ:
            незнайомі.append("%s: дія поза переліком" % де)
            continue
        оп = д["op"]
        if оп == "add":
            поля = _поля_дії(д, де, незнайомі)
            if not поля.get("слот"):
                незнайомі.append("%s: нова річ без місця" % де)
                continue
            видано += 1
            р = dict(ід="н%d" % видано, фото=None, вид=None, назва=None, слот=None, колір=None,
                     матеріал=None, крій=None, довжина=None, принт=None, ошатність=None, чия="невідомо", в_образі=True,
                     рамка=None, джерело=ДЖЕРЕЛО_ЇЇ)
            змінити(р, поля, оп)
            р.pop("виправлено", None)         # нова річ — `джерело`, а не «виправлено»
            поточні.append(р)
            continue
        ід = ід_з_дроту(str(д.get("item") or ""))
        р = next((х for х in поточні if х["ід"] == ід), None)
        if р is None:
            незнайомі.append("%s: річ «%s» не знайдена" % (де, д.get("item")))
        elif оп == "remove":
            звіт.append(dict(op=оп, ід=ід, поле="річ", було=р.get("слот"), стало=None))
            поточні.remove(р)
        else:
            змінити(р, _поля_дії(д, де, незнайомі, р), оп)
    return dict(речі=поточні, дії=звіт, незнайомі=незнайомі, лічильник=видано)


def речі_для_слів(речі):
    """Перелік (ключі ядра) → `КОНТЕКСТ.items` перекладача, що виправляє перелік її словами: ід дроту, місце,
    вид, колір і «в образі» — кодами внутрішньої мови; назва — слово моделі з фото вільним текстом (перекладач бачить, про
    яку річ мова, код її не читає, п.12). Поле, якого в речі нема, — "unknown"."""
    U = _ВМ.UNKNOWN
    вих = []
    for р in речі or []:
        if not isinstance(р, dict) or not р.get("ід"):
            continue
        вих.append(dict(id=ід_на_дріт(р["ід"]), slot=_ВМ.код("slot", р.get("слот")) or U,
                        item_type=р["вид"] if р.get("вид") in _ВМ.ТАБЛИЦЯ["item_type"] else U,
                        color_name=_ВМ.код("color_name", р.get("колір")) or U,
                        in_outfit=U if р.get("в_образі") is None else bool(р["в_образі"]),
                        name=_ВМ.вільний(р["назва"], "en") if р.get("назва") else U))
    return вих


# ═══════════ 3. ОБРАЗ: ОДНА РІЧ НА МІСЦЕ, РЕШТА — ЇЇ ЗАПАСНІ ══════════════════════
def займають_одне(слот_а, слот_б):
    """Чи дві речі не стоять в одному образі разом: той самий слот, або слот однієї — серед
    місць, які займає інша (`річ_з_фото.займає`: сукня займає верх і низ).

    ЧОМУ НЕ ПЕРЕТИН `займає(а) & займає(б)`. Верх займає {верх, сукня, комплект}, низ — {низ,
    сукня, комплект}: перетин непорожній, і верх із низом виходили б однією річчю на одне місце,
    хоч образ «верх + низ» — звичайний. Сукня з верхом справді не стоять: «верх» ∈ займає(сукня)."""
    if not слот_а or not слот_б:
        return False
    return слот_а == слот_б or слот_а in _РФ.займає(слот_б) or слот_б in _РФ.займає(слот_а)


def скласти(речі):
    """Речі з фото → (образ, запасні, конфлікти) ідами.

    Образ — речі «in_outfit» по одній на місце в структурі (`займають_одне`). Друга річ на те
    саме місце — не друга сукня в образі, а її запасна: код пробує її як зміну. Хто переміг,
    названо в `конфлікти` (перша за порядком фото — бо так вона їх показала). Річ без слота в
    образ не стає: їй нема місця, і це сказано."""
    образ, запасні, конфлікти, слоти = [], [], [], {}
    for р in речі or []:
        if (р.get("вимір") or {}).get("причина") == ПРИЧИНА_ДІЛЯНКИ:
            конфлікти.append(dict(річ=р["ід"], чому=ПРИЧИНА_ДІЛЯНКИ))
            continue
        сл = р.get("слот")
        if not сл:
            конфлікти.append(dict(річ=р["ід"], чому="no_slot"))
            continue
        if р.get("в_образі", True) is False:
            запасні.append(р["ід"])
            continue
        хто = sorted(і for і, с in слоти.items() if займають_одне(сл, с))
        if хто:
            запасні.append(р["ід"])
            конфлікти.append(dict(річ=р["ід"], чому="same_place", з=хто))
            continue
        образ.append(р["ід"])
        слоти[р["ід"]] = сл
    return образ, запасні, конфлікти


