def _перелік(речі):
    """Речі з фото → {ід: hex кружечка в переліку «Що я бачу на фото»} — центр вікна її слова (`річ_з_фото`:
    слово → вікно ядра). Вимір кадру дає `суд` (далі, поверх); тут лише число з таблиці, без пікселів: перелік
    стоїть до суду й не стоїть у ланцюгу. Слова без вікна — None (кружечок порожній)."""
    вих = {}
    for р in речі or []:
        if not isinstance(р, dict) or not р.get("ід"):
            continue
        вікно = _V.ЛЕКСИКОН.get(р.get("колір"))
        вих[р["ід"]] = _cs.hex_з_lab(tuple(_ПЛ.центр(вікно))) if вікно else None
    return вих


def суд_кроками(d):
    """Її речі з фото → образ, вимір, суд цілим, перевірені зміни, «без входу» — усе кодами.

    `d`: вхід показу (колір, мірки, драпіровка) + `речі` (з `речі_з_відповіді`) + `пікселі`
    {ід: кадр} + `сценарій` (лише названі поля) + `крамниця` (шукати зміни в каталозі).

    Генератор (див. `_ганяти`): суд у Pyodide займає головний потік сторінки на 5–6 с, і дотик жінки «Так, оцінюй»
    чекав його кінця; тепер між кроками, кожен з яких до 0,6 с, потік вільний."""
    F, T, d = профіль(d)
    сц, звідки = сценарій_оцінки(d.get("сценарій_оцінки"), d.get("сценарій_слів"), d.get("сценарій_паспорта"),
                                       плитки=d.get("сценарій_плитки"))
    сцен, незн = _сцена(сц, d)
    палітра = _ПЛ.палітра_практична(F, source=d.get("source") or "uncontrolled",
                                    intent=сцен.get("intent") or "conventional",
                                    насиченість=(d.get("вибір_кольору") or {}).get("насиченість"))
    yield
    шкіра = (F.get("шкіра") or {}).get("hex")
    речі = _слово_сильніше(_без_кадру((yield from _виміри_кроками(d.get("речі"), d.get("пікселі") or {},
                                                                  d.get("пікселі_фото") or {}, шкіра))))
    for р in речі:
        lab = _КР_ТИП.точка_кольору(р.get("вимір") or {})
        р["біля_обличчя"] = _РФ.біля_обличчя(р.get("слот"))
        if lab:
            р["палітра"] = _РФ.членство_в_палітрі(р["вимір"], палітра)
    за_ід = {р["ід"]: р for р in речі}
    образ, запасні, конфлікти = скласти(речі)
    драп = d.get("драп") or None
    вих = dict(речі=речі, образ=образ, запасні=запасні, конфлікти=конфлікти,
               сцена={к: v for к, v in сцен.items() if not str(к).startswith("_") and к != "самозвіт"},
               сцена_звідки=звідки, незнайомі_поля=незн)
    if not образ:
        вих.update(суд=dict(findings=[], blockers=[], checklist={}), рівень="clean", зміни=[],
                   без_входу=_без_входу({}, сцен, речі), чому="no_item_with_slot")
        return вих
    записи = [_РФ.запис_каталогу(dict(за_ід[і], закріплена=True)) for і in образ]
    yield
    о = _ваги_образу([з["id"] for з in записи], записи, F, T, сцен, драп)
    yield
    о["чеклісти"] = _СЧ.не_цієї_фази(о.get("чеклісти"))      # збирання образу — не ця фаза
    знахідки, вето = _знахідки(о, за_ід)
    блокери = [б for б in (_PL.блокери_структури(о.get("блокує") or [], о.get("речі") or [], {},
                                                  заяви=о.get("заяви_блокерів")) + вето)]
    # «на фото нема» — не вада й не gate (блокери повноти, одна річ, K-SHO-01, пальто в
    # холод); рівень — від справжніх гейтів
    о, блокери, відсутнє = _СЧ.відсутнє_на_фото(о, блокери, {з.get("слот") for з in записи})
    знахідки, _ = _знахідки(о, за_ід)       # без знахідок «на фото нема»; вето вже в блокерах
    for б in блокери:
        б["речі"] = [_до_фото(х, за_ід) for х in (б.get("речі") or [])]
    вих["суд"] = dict(findings=знахідки, blockers=блокери,
                      checklist=_PL.чекліст_вердикту(о.get("чеклісти")),
                      node=о.get("вузол"), weight=о.get("сума_сил"))
    вих["рівень"] = рівень(вих["суд"])
    вих["не_на_фото"] = відсутнє
    вих["пункти"] = _пункти(о)
    вих["без_входу"] = _без_входу(о, сцен, речі)
    обличчя = _контраст_обличчя(F, T, записи, d.get("source") or "uncontrolled")
    if обличчя.get("пункт"):
        вих["пункти"].append(обличчя["пункт"])
    if обличчя.get("без_входу"):
        вих["без_входу"].append(обличчя["без_входу"])
    вих["зміни"], вих["зміни_звіт"] = yield from зміни_кроками(
        d, F, T, сцен, речі, образ, запасні, о, палітра, драп, крамниця=bool(d.get("крамниця")) and bool(d.get("каталог")))
    return вих


def суд(d):
    """`суд_кроками`, доведений до кінця за один виклик (проби, батарея, не-Pyodide)."""
    return _ганяти(суд_кроками(d))


async def суд_без_блоку(d):
    """`суд_кроками` у Pyodide: між кроками — `asyncio.sleep(0)`, тобто хід головному потоку сторінки (дотик жінки,
    малювання). Той самий результат, що в `суд`; різниця лише в тому, чи сторінка чує дотики, поки суд іде. Крок
    «крамниця» чекає кінця прогріву каталогу (`прогріти_каталог_без_блоку`), вітрина — його покажчиків
   ."""
    г, слід = суд_кроками(d), _СЛ.свій_слід()    # слід — свій на весь суд
    _ЦИКЛ["суд"] += 1
    try:
        while True:
            крок = _СЛ.у_своєму(слід, next, г)
            if крок is _КРОК_КРАМНИЦЯ or крок is _КРОК_ВІТРИНА:
                # крамниці потрібен каталог, вітрині — покажчики; потік — прогріву, доки його фаза
                # не скінчиться
                фаза = "прогрів" if крок is _КРОК_КРАМНИЦЯ else "вітрина"
                _ЦИКЛ["суд_чекає"] += 1
                try:
                    while _ЦИКЛ[фаза]:
                        await _asyncio.sleep(0.01)
                finally:
                    _ЦИКЛ["суд_чекає"] -= 1
            await _asyncio.sleep(0)
    except StopIteration as к:
        return к.value
    finally:
        _ЦИКЛ["суд"] -= 1
        _ЦИКЛ["судів"] += 1


