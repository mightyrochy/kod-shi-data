def суд(d):
    """Її речі з фото → образ, вимір, суд цілим, перевірені зміни, «без входу» — усе кодами.

    `d`: вхід показу (колір, мірки, драпіровка) + `речі` (з `речі_з_відповіді`) + `пікселі`
    {ід: кадр} + `сценарій` (лише названі поля) + `крамниця` (шукати зміни в каталозі)."""
    F, T, d = _профіль(d)
    сц, звідки = сценарій_оцінки(d.get("сценарій_оцінки"), d.get("сценарій_слів"))
    сцен, незн = _сцена(сц, d)
    import palettes as _ПЛ
    палітра = _ПЛ.палітра_практична(F, source=d.get("source") or "uncontrolled",
                                    intent=сцен.get("intent") or "conventional")
    шкіра = (F.get("шкіра") or {}).get("hex")
    пікселі = d.get("пікселі") or {}
    речі = []
    for р in d.get("речі") or []:
        if not isinstance(р, dict) or not р.get("ід"):
            continue
        р = dict(р)
        if пікселі.get(р["ід"]):
            р["вимір"] = _РФ.виміряти(пікселі[р["ід"]], слово_моделі=р.get("колір"),
                                      шкіра_hex=шкіра, рамка=р.get("рамка"))
        lab = (р.get("вимір") or {}).get("lab")
        р["біля_обличчя"] = _РФ.біля_обличчя(р.get("слот"))
        if lab:
            р["палітра"] = _РФ.членство_в_палітрі(lab, палітра)
        речі.append(р)
    за_ід = {р["ід"]: р for р in речі}
    образ, запасні, конфлікти = скласти(речі)
    драп = d.get("драп") or None
    вих = dict(речі=речі, образ=образ, запасні=запасні, конфлікти=конфлікти,
               сцена={к: v for к, v in сцен.items() if not str(к).startswith("_") and к != "самозвіт"},
               сцена_звідки=звідки, незнайомі_поля=незн)
    if not образ:
        вих.update(суд=dict(findings=[], blockers=[], checklist={}), рівень="clean", зміни=[],
                   без_входу=_без_входу({}, сцен, речі), чому="в образі нема жодної речі зі слотом")
        return вих
    записи = [_РФ.запис_каталогу(dict(за_ід[і], закріплена=True)) for і in образ]
    о = _ваги_образу([з["id"] for з in записи], записи, F, T, сцен, драп)
    import pipeline as _PL
    знахідки, вето = _знахідки(о, за_ід)
    блокери = [б for б in (_PL.блокери_структури(о.get("блокує") or [], о.get("речі") or [], {}) + вето)]
    for б in блокери:
        б["речі"] = [_до_фото(х, за_ід) for х in (б.get("речі") or [])]
    вих["суд"] = dict(findings=знахідки, blockers=блокери,
                      checklist=_PL.чекліст_вердикту(о.get("чеклісти")),
                      node=о.get("вузол"), weight=о.get("сума_сил"))
    вих["рівень"] = рівень(вих["суд"])
    вих["пункти"] = _пункти(о)
    вих["без_входу"] = _без_входу(о, сцен, речі)
    обличчя = _контраст_обличчя(F, T, записи, d.get("source") or "uncontrolled")
    if обличчя.get("пункт"):
        вих["пункти"].append(обличчя["пункт"])
    if обличчя.get("без_входу"):
        вих["без_входу"].append(обличчя["без_входу"])
    вих["зміни"], вих["зміни_звіт"] = зміни(d, F, T, сцен, речі, образ, запасні, о, палітра, драп,
                                           крамниця=bool(d.get("крамниця")) and bool(d.get("каталог")))
    return вих


