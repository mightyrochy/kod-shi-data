# Екземпляр — річ суду під своїм ідом: фото й місце на ньому (рамка чи її дотик), вимір, місце в образі. Цей ід несуть
# відповідь моделі (`ід_на_дріт`), вимір, суд і картка; перенос міняє фото й рамку, ід лишається.
# ЩО БУЛО. Яка річ підпирає «що вдало», вирішували два місця кожне по-своєму: `опори_вдалого` (вхід моделі) і
# `_суперечить` (сторож картки). Опори брали для «кольори разом» дві виміряні речі, сторож пропускав одну;
# опори брали для контрасту речі біля обличчя, сторож — будь-які. На записаних відповідях живих 14, 15, 22, 24, 25, 27
# (40 викликів, `проби/реєстр_тверджень_6_2.py`) сторож пропустив на картку 3 «контрасти» верху з бордовим низом чи
# ботильйонами і 1 «кольори разом» про одну річ. Пункт без жодного ід сторож судив проти всього образу. ТЕПЕР обидва читають реєстр через `_підпора`, а твердження без названого екземпляра,
# з екземпляром без потрібної ознаки чи з одним на пару — відхилено. Слів моделі код і тут не читає (п.12): лише чи
# екземпляр є, чи в образі й чи виміряний.
def екземпляри(суд_):
    """Реєстр екземплярів суду: ід → місце на фото, стан ділянки й опори суду."""
    образ = set(суд_.get("образ") or [])
    return {р["ід"]: dict(фото=р.get("фото"), рамка=р.get("рамка"), дотик=bool(р.get("дотик")),
                          причина_ділянки=(р.get("вимір") or {}).get("причина"),
                          слот=р.get("слот"), в_образі=р["ід"] in образ,
                          виміряно=bool(_КР_ТИП.точка_кольору(р.get("вимір") or {})),
                          у_палітрі=((р.get("палітра") or {}).get("стан") == "у палітрі"),
                          біля_обличчя=bool(р.get("біля_обличчя")))
            for р in суд_.get("речі") or [] if isinstance(р, dict) and р.get("ід")}


def _підпора(про, суд_, екз=None):
    """Екземпляри образу (у його порядку), що мають ознаку, на якій стоїть `про` (`_ПІДПОРА`), — до знахідок суду."""
    екз = екземпляри(суд_) if екз is None else екз
    ознака = (_ПІДПОРА.get(про) or (None,))[0]
    return [і for і in суд_.get("образ") or [] if і in екз and (ознака is None or екз[і][ознака])]


def _суперечить(про, речі, суд_):
    """Чому твердження «вдало» (`про`, речі) суперечить суду коду чи реєстру екземплярів, або None."""
    нема = {б.get("input") for б in суд_.get("без_входу") or []}
    if про in ПРО_БЕЗ_ВХОДУ and ПРО_БЕЗ_ВХОДУ[про] in нема:
        return "no_input:%s" % ПРО_БЕЗ_ВХОДУ[про]
    if not речі:
        return "no_instance"
    префікси = ПРО.get(про) or ()
    for з in (суд_.get("суд") or {}).get("findings") or []:
        if з.get("регістр") not in ("гейт", "репліка") or not (з.get("сила_нп") or 0) > 0:
            continue
        if str(з.get("правило") or "").startswith(префікси) and set(з.get("речі") or []) & set(речі):
            return "finding:%s:%s" % (з.get("ід"), з.get("правило"))
    for п in суд_.get("пункти") or []:
        if п.get("стан") == "провал" and any(str(х).startswith(префікси) for х in п.get("правила") or []):
            return "failed_point:%s:%s" % (п.get("бік"), п.get("пункт"))
    # ЕКЗЕМПЛЯР ПІД ТВЕРДЖЕННЯМ: «колір — твій» — лише виміряний колір у її палітрі («на межі», «поза» й колір без
    # виміру — не успіх палітри); «пасують» — лише між виміряними кольорами, і їх два;
    # контраст K-CLR-02 — з обличчям, тож про речі біля нього
    підпора = set(_підпора(про, суд_))
    поза = [і for і in речі if і not in підпора]
    if поза:
        return "%s:%s" % ((_ПІДПОРА.get(про) or (None, "no_instance"))[1], ",".join(поза))
    if len(set(речі)) < МІН_ЕКЗЕМПЛЯРІВ.get(про, 1):
        return "pair_without_two_items:%s" % ",".join(речі)
    if про == "contrast" and not any(п.get("стан") == "пройдено" and "K-CLR-02" in (п.get("правила") or [])
                                     for п in суд_.get("пункти") or []):
        return "no_check:K-CLR-02"
    return None


def опори_вдалого(суд_):
    """«Що вдало», яке суд коду підтримує: [{about, items}] — для кожного `about` ті речі образу, проти яких
    нема знахідки його сім'ї (палітра — лише речі «у палітрі», контраст — речі біля обличчя), і саме таке
    твердження `_суперечить` пропустив би. Порожньо — суд не підтримує жодного «вдало».

    ЧОМУ. Правило промпта «claim a success only where the check supports it» модель читала, а
    вибирати опору мусила сама: кожне «вдало» картки 6 сторож зняв (палітра з хакі «на межі»,
    контраст проти проваленого K-CLR-02, «кольори разом» проти K-COL-01), і картка йшла без «Що вдало». Тепер
    опори стоять у вході кодами, а пункт поза ними — один повтор (`повтор_вдалого`)."""
    екз = екземпляри(суд_)
    знахідки = [з for з in (суд_.get("суд") or {}).get("findings") or []
                if з.get("регістр") in ("гейт", "репліка") and (з.get("сила_нп") or 0) > 0]
    вих = []
    for про, префікси in ПРО.items():
        влучені = {і for з in знахідки if str(з.get("правило") or "").startswith(префікси) for і in з.get("речі") or []}
        речі = [і for і in _підпора(про, суд_, екз) if і not in влучені]
        if len(речі) >= МІН_ЕКЗЕМПЛЯРІВ.get(про, 1) and _суперечить(про, речі, суд_) is None:
            вих.append({"about": про, "items": речі})
    return вих


def повтор_вдалого(суд_, картка):
    """Рядок для ОДНОГО повтору, коли на картці нема «що вдало», а суд його підтримує (`опори_вдалого`)."""
    опори = опори_вдалого(суд_)
    if not опори or not картка or (картка.get("вдало") or []):
        return None
    return (_json.dumps(dict(reason="works_missing", supported=_ід_усюди(опори)), ensure_ascii=False)
            + "\n" + _ФФ.ПОВТОР_ЛИШЕ_JSON_EN)


def сторож_оцінки_об(об, суд_, причина=None, нотатки=None):
    """Сторож оцінки образу: валідація об'єкта відповіді проти фактів суду."""
    if not isinstance(об, dict):
        return dict(картка=None, сторож=[], причина=причина or "no_json_object", нотатки=нотатки)
    сторож = []
    образ = set(суд_.get("образ") or [])
    запасні = set(суд_.get("запасні") or [])
    вердикт = об.get("verdict") if об.get("verdict") in ВЕРДИКТИ else None
    if об.get("verdict") not in (None, "") and вердикт is None:
        сторож.append(dict(де="verdict", чому="code_outside_list", що=об.get("verdict")))
    рів = суд_.get("рівень") or "clean"
    if вердикт == "wear_as_is" and рів == "gate":
        сторож.append(dict(де="verdict", чому="contradicts_gate", що=вердикт))
    вдало = []
    for н, п in enumerate(об.get("works") if isinstance(об.get("works"), list) else []):
        if not isinstance(п, dict):
            continue
        про = п.get("about") if п.get("about") in ПРО else None
        названі = _названі(п.get("items"))
        речі = [і for і in названі if і in образ]
        текст = _без_ід(п.get("text"))
        if not текст:
            if _текст(п.get("text")):
                сторож.append(dict(де="works[%d]" % н, чому="id_in_text", текст=_текст(п.get("text"))))
            continue
        if про is None:
            сторож.append(dict(де="works[%d]" % н, чому="about_outside_list", що=п.get("about"), текст=текст))
            continue
        # ОЦІНКА-3321 (п.12): текст «що вдало» говорить про річ, якої в образі нема (її ід — поза образом), —
        # запис не йде жінці: слів код не читає, а ід, за якими модель назвала речі, читає. Одного ід поза
        # образом досить: решта ід не каже, чи не про ту саму річ текст
        поза = [і for і in названі if і not in образ]
        if поза:
            сторож.append(dict(де="works[%d]" % н, чому="items_not_in_outfit", що=поза, текст=текст))
            continue
        # пункт без жодного ід — ні про що з її фото (реєстр, `_суперечить`: `no_instance`), а не про весь образ
        чому = _суперечить(про, речі, суд_)
        if чому:
            сторож.append(dict(де="works[%d]" % н, чому=чому, про=про, речі=речі, текст=текст))
            continue
        вдало.append(dict(про=про, речі=речі, текст=текст))
    зміни = {с["ід"]: с for с in суд_.get("зміни") or []}
    # РЕМОНТ ЗНАХІДКИ — ТЕЖ «ЩО ЗМІНИТИ»: знахідка суду з ремонтом, який вона зробить сама
    # («додай шар чи сильний аксесуар»), стоїть у «change» своїм ідом; речі для неї нема, тож показ малює
    # лише текст. Знахідка без ремонту зміною не стає.
    ремонти = {з.get("ід") for з in (суд_.get("суд") or {}).get("findings") or []
               if з.get("ід") and (з.get("ремонт_заяви") or з.get("ремонт"))}
    змінити = []
    for н, з in enumerate(об.get("change") if isinstance(об.get("change"), list) else []):
        if not isinstance(з, dict):
            continue
        ід = ід_з_дроту(str(з.get("id") or ""))
        if ід not in зміни and ід not in ремонти:
            сторож.append(dict(де="change[%d]" % н, чому="change_not_verified", що=ід, текст=_текст(з.get("text"))))
            continue
        # та сама межа для «що змінити»: її речі, про які текст, — з образу чи з її запасних; ід поза ними —
        # запис знято (без дійсної зміни «wear_with_change» піде в повтор — `change_missing` нижче)
        названі = _названі(з.get("items"))
        поза = [і for і in названі if і not in образ and і not in запасні]
        if поза:
            сторож.append(dict(де="change[%d]" % н, чому="items_not_in_outfit", що=поза, ід=ід,
                               текст=_текст(з.get("text"))))
            continue
        # ЗМІНА ↔ РІЧ — ІДАМИ: «items» перевіреної зміни мусять нести річ, яку вона міняє. Приклади:
        # «Обмін… ботильйонів на бежеві…» з items [p2] над спідницею крамниці, що міняє спідницю (6б Ж:01), «Заміни
        # бежеві чоботи на… босоніжки» з items верху й низу (6б Ж:10). Слів код не читає: про ту саму річ текст чи
        # ні, кажуть лише ід. Ціль перевіреної зміни код знає сам: на живих 1016-1 із 6 знятих так
        # записів 4 мали текст про ту саму річ, тож «items» ставить код — ціль зміни, — а запис лишається; про що
        # текст, судить живий прогін, сторож лише записує поставлене
        if ід in зміни and зміни[ід]["ціль"] not in названі:
            сторож.append(dict(де="change[%d]" % н, чому="items_not_target", що=названі, ід=ід,
                               ціль=зміни[ід]["ціль"], текст=_текст(з.get("text"))))
            названі = [зміни[ід]["ціль"]]
        if len(змінити) >= 2 or any(с["ід"] == ід for с in змінити):
            сторож.append(dict(де="change[%d]" % н, чому="over_two_or_repeat", що=ід))
            continue
        текст = _без_ід(з.get("text"))
        if _текст(з.get("text")) and not текст:
            сторож.append(dict(де="change[%d]" % н, чому="id_in_text", ід=ід, текст=_текст(з.get("text"))))
        if ід not in зміни and not текст:
            сторож.append(dict(де="change[%d]" % н, чому="fix_without_text", що=ід))
            continue
        змінити.append(dict(ід=ід, речі=названі, текст=текст, зміна=зміни.get(ід)))
    # «з зміною» без жодної дійсної зміни — твердження без опори: сторож знімає вердикт (як код поза
    # переліком), а показ іде в ОДИН повтор із названими ідами (`повтор_вердикту`)
    if вердикт == "wear_with_change" and not змінити:
        сторож.append(dict(де="verdict", чому="change_missing", що=вердикт))
        вердикт = None
    # блок «Чого я не знаю» — від коду лише позначки «немає входу» кодами (п.12): слова дає
    # мовний прохід картки; лише те, що стосується цього образу, не повний звіт власника
    не_знаю, бачено = [], set()
    назви = {р.get("ід"): _текст(р.get("назва")) for р in суд_.get("речі") or []}
    for б in позначки_без_входу(суд_):
        входи = _коди_без_входу(б)
        ключ = tuple(входи) + (б.get("why"),) if входи else _вільний_текст_без_входу(б)
        if ключ and ключ not in бачено:
            бачено.add(ключ)
            не_знаю.append(dict(входи=входи, чому=б.get("why"), речі=list(б.get("items") or []),
                                дані=_дані_заяви(б, назви)) if входи else dict(текст=ключ))
    відповідь = _без_ід(об.get("answer"))
    if not відповідь:
        відповідь = next((п["текст"] for п in вдало + змінити if п["текст"]), "")
    картка = dict(відповідь=відповідь, вердикт=вердикт, вдало=вдало,
                  змінити=змінити, не_знаю=не_знаю, речі_шару=речі_для_шару(суд_, змінити),
                  нема_на_фото=dict(коди=_СЧ.коди_нема_на_фото(суд_.get("не_на_фото") or [], лише_речі=True)))
    return dict(картка=картка, сторож=сторож,
                причина=(None if картка["відповідь"] else "empty_answer_field"), нотатки=нотатки,
                # межа сторожа — кодами полів, не фразою (аудит/ПРОДУКТ.md п.12)
                сторож_межа=dict(звіряє=["about", "items", "change_id", "verdict", "answer"],
                                 не_читає=["text"]))


def прийняти_оцінку(відповідь, суд_):
    """Відповідь задачі `ОЦІНКА` → {картка, сторож, причина}; розбір і сторож — форми `OUTFIT_REVIEW_V1`
    (`схема_відповіді`).

    Картка — поля, які показ пише жінці (після мовної моделі): `відповідь`, `вдало`,
    `змінити`, `не_знаю`, і `вердикт` (код для звіту). Сторож звіряє КОДИ твердження з судом
    коду й знімає те, чому суд суперечить; кожне зняте — рядком у `сторож` зі своєю причиною
    (звіт власника без стелі). Слів відповіді код не читає: суперечність у самому тексті
    «answer» сторож не бачить, і це сказано у звіті полем `сторож_межа` (які поля звіряє, яких не читає)."""
    об, причина, нотатки = _СВ.схема_за_назвою("OUTFIT_REVIEW_V1").виконати_розбір(відповідь)
    # сторож форми — `_сторож_оцінки_об` цього модуля: `схеми_розбору` прив'язує його до форми для мосту (3.3)
    return сторож_оцінки_об(об, суд_, причина=причина, нотатки=нотатки)


def повтор_вердикту(суд_, сторож):
    """Рядок для ОДНОГО повтору, коли `verdict` суперечить суду: «як є» проти гейта або «з зміною» без
    дійсної зміни (`change_missing`) — що саме в суді, кодами."""
    чому = {с.get("чому") for с in сторож or []}
    if "change_missing" in чому and "contradicts_gate" not in чому:
        зміни = [ід_на_дріт(с.get("ід")) for с in суд_.get("зміни") or []]
        ремонти = [ід_на_дріт(з.get("ід")) for з in (суд_.get("суд") or {}).get("findings") or []
                   if з.get("ід") and (з.get("ремонт_заяви") or з.get("ремонт"))]
        її = [ід_на_дріт(і) for і in (суд_.get("образ") or []) + (суд_.get("запасні") or [])]
        дані = dict(reason="change_missing", verified_changes=зміни, findings_with_fix=ремонти)
        if "items_not_in_outfit" in чому:
            дані["her_items"] = її
        return _json.dumps(дані, ensure_ascii=False) + "\n" + _ФФ.ПОВТОР_ЛИШЕ_JSON_EN
    if "contradicts_gate" not in чому:
        return None
    гейти = [ід_на_дріт(з.get("ід")) for з in (суд_.get("суд") or {}).get("findings") or []
             if з.get("регістр") == "гейт" or з.get("без_замків")]
    блок = [_ДМ.код_переліку(_ДМ.БЛОКЕР, б.get("код")) for б in (суд_.get("суд") or {}).get("blockers") or []]
    return (_json.dumps(dict(reason="contradicts_gate", blocking_findings=гейти, structure_blockers=блок),
                        ensure_ascii=False) + "\n" + _ФФ.ПОВТОР_ЛИШЕ_JSON_EN)
