def _довжини():
    """Код довжини → рівень ядра: `ТАБЛИЦЯ["length"]` дає слово довжини каталогу («до коліна»),
    а рівнем його робить зворотний бік `пакет_моделі.ДОВЖИНА_СЛОВОМ` — дві наявні таблиці, без
    третьої. Рівень іде в `довжина` речі: `річ_з_фото.запис_каталогу` кладе його в
    `довжина_рівень`, яким композитор рахує край на тілі."""
    import пакет_моделі as _ПМ
    рівень = {слово: р for р, слово in _ПМ.ДОВЖИНА_СЛОВОМ.items()}
    return {к: рівень[сл] for к, сл in _ВМ.ТАБЛИЦЯ["length"].items() if сл in рівень}


def коди_речей():
    """Дозволені коди полів речі для промпта `РЕЧІ`: {поле: [коди]}."""
    вих = {}
    for поле, таблиця, словник in _ПОЛЯ_КОДІВ:
        вих[поле] = [к for к, ключ in _ВМ.ТАБЛИЦЯ[таблиця].items() if ключ in словник]
    вих["cut"] = list(_РФ.КРОЇ)
    вих["length"] = list(_довжини())
    # «solid» у таблиці візерунків має ключем сам себе, а `річ_з_фото` зве однотонне
    # «однотонний» — той самий виняток, що в `мовний_шар._фраза`
    вих["pattern"] = [к for к, ключ in _ВМ.ТАБЛИЦЯ["pattern"].items()
                      if ключ in _РФ.ПРИНТИ or ключ == "solid"]
    return вих


def _ключ(поле, код, незнайомі, де):
    """Код моделі → ключ ядра через таблицю; код поза переліком — None і рядок у `незнайомі`."""
    if _ВМ.невідомо(код):
        return None
    таблиця, словник = next(((т, с) for п, т, с in _ПОЛЯ_КОДІВ if п == поле), (None, None))
    if таблиця:
        к = _ВМ.ключ(таблиця, код)
        if к in словник:
            return к
    elif поле == "cut":
        if str(код) in _РФ.КРОЇ:
            return str(код)
    elif поле == "length":
        р = _довжини().get(str(код))
        if р:
            return р
    elif поле == "pattern":
        к = _ВМ.ключ("pattern", код)
        к = "однотонний" if к == "solid" else к
        if к in _РФ.ПРИНТИ:
            return к
    незнайомі.append("%s.%s: код «%s» поза переліком" % (де, поле, код))
    return None


