def рівень(суд):
    """Рівень суду коду для сторожа: «gate» — блокер структури чи гейт (і гейт, знятий «без
    замків»: річ її, але вага гейта та сама); «remarks» — знахідки, що промовляються; «clean»."""
    if суд.get("blockers") or any(з.get("регістр") == "гейт" or з.get("без_замків")
                                  for з in суд.get("findings") or []):
        return "gate"
    if any(з.get("регістр") == "репліка" and (з.get("сила_нп") or 0) > 0 for з in суд.get("findings") or []):
        return "remarks"
    return "clean"


def _цілі(знахідки, речі, образ):
    """Речі образу, проти яких найважчі знахідки: сума `сила_нп` знахідок, що їх називають, плюс
    колір поза палітрою біля обличчя (K-PAL-17 soft). Повертає до `ЦІЛЕЙ` ідів за спаданням ваги."""
    вага = {і: 0.0 for і in образ}
    for з in знахідки:
        if з.get("регістр") not in ("гейт", "репліка"):
            continue
        for і in set(з.get("речі") or []):
            if і in вага:
                вага[і] += float(з.get("сила_нп") or 0.0)
    for р in речі:
        п = р.get("палітра") or {}
        if р["ід"] in вага and п.get("стан") == "поза палітрою" and р.get("біля_обличчя"):
            вага[р["ід"]] += 1.0 - float(п.get("сила") or 0.0)
    return [і for і, в in sorted(вага.items(), key=lambda х: -х[1]) if в > 0][:ЦІЛЕЙ]


def _заміна(образ, за_ід_речей, ціль, нова_ід, нова_слот):
    """Образ, у якому на місці цілі стоїть нова річ (і знято все, з чим вона разом не стоїть)."""
    лишити = [і for і in образ if і != ціль and not займають_одне(за_ід_речей[і]["слот"], нова_слот)]
    return лишити + [нова_ід]


def _правила(о):
    """Правила знахідок, що промовляються (гейт чи репліка з вагою), — для «що зняла зміна».
    Рівнем правила, а не пари (правило, речі): нова річ має інший ід, і та сама вада на ній —
    не «знято й додано», а «лишилось»."""
    return {з.get("правило") for з in (о.get("знахідки") or []) if isinstance(з, dict)
            and з.get("регістр") in ("гейт", "репліка") and (з.get("сила_нп") or 0) > 0}


def _крамниця(d, F, T, сцен, слоти):
    """Кандидати крамниці для слотів цілей: пул рук (коли нагоду названо), інакше каталог
    цього слота. Повертає ({слот: [записи]}, чому, пак_готовий)."""
    import міст_пакет as _МП
    import міст_основи as _МО
    from міст_вхід import _збірка
    dd = dict(d, сценарій={к: v for к, v in сцен.items() if not str(к).startswith("_")
                           and к in ("нагода", "місце", "дрес_код", "темп_c", "опади", "година")})
    dd.pop("паспорт", None)
    F2, T2, зріст, kw = _збірка(dd)
    п, гілка, _сх, _під = _МО._пакет_гілки(dd, F2, T2, зріст, kw, None, dd.get("намір") or "conventional")
    пак = _МП._пакет_каталогу(dd, F2, T2, п, (0 if гілка is None else гілка), за_замовчуванням=(гілка is None))
    if пак.get("готово") and пак.get("кандидати"):
        return {с: list(пак["кандидати"].get(с) or []) for с in слоти}, None, True, пак
    кат = пак.get("_каталог") or []
    return ({с: [r for r in кат if r.get("слот") == с] for с in слоти},
            пак.get("чому") or "пулу нема", False, пак)


def зміни(d, F, T, сцен, речі, образ, запасні, о0, палітра, драп=None, крамниця=True):
    """Перевірені зміни: її запасна річ, потім річ крамниці на місце цілі; образ переважується
    тим самим судом, лишаються ті, що зменшують `сума_сил`. Повертає (зміни, звіт)."""
    за_ід = {р["ід"]: р for р in речі}
    записи = {р["ід"]: _РФ.запис_каталогу(dict(р, закріплена=True)) for р in речі}
    зн0, _ = _знахідки(о0, за_ід)
    цілі = _цілі(зн0, речі, образ)
    звіт = dict(цілі=цілі, сума_до=о0.get("сума_сил"), спроби=[], крамниця=None)
    if not цілі:
        return [], звіт
    сума0 = float(о0.get("сума_сил") or 0.0)
    правила0 = _правила(о0)
    свої, крамні = [], []

    def _спроба(ціль, нова_ід, нова_слот, запис, звідки):
        ід = _заміна(образ, за_ід, ціль, нова_ід, нова_слот)
        кат = [записи[і] for і in ід if і in записи] + ([запис] if нова_ід not in записи else [])
        о1 = _ваги_образу([з["id"] for з in кат], кат, F, T, сцен, драп)
        сума1 = float(о1.get("сума_сил") or 0.0)
        знято = sorted(правила0 - _правила(о1))
        додано = sorted(_правила(о1) - правила0)
        спроба = dict(ціль=ціль, нова=нова_ід, звідки=звідки, сума=round(сума1, 3),
                      дельта=round(сума1 - сума0, 3), знято=знято, додано=додано)
        звіт["спроби"].append(спроба)
        return спроба if сума1 < сума0 else None

    for ціль in цілі:
        сл = за_ід[ціль]["слот"]
        for з in запасні:
            if займають_одне(за_ід[з]["слот"], сл):
                с = _спроба(ціль, з, за_ід[з]["слот"], записи[з], "own")
                if с:
                    свої.append(с)
    if крамниця:
        слоти = sorted({за_ід[ц]["слот"] for ц in цілі})
        try:
            пули, чому, готовий, _пак = _крамниця(d, F, T, сцен, слоти)
        except (KeyError, TypeError, ValueError) as е:
            # П.14: каталог — чужий вхід (показ може бути зібраний без нього); оцінка
            # стоїть і без крамниці, а причина — у звіті, не мовчанням
            пули, чому, готовий = {}, "%s: %s" % (type(е).__name__, е), False
        звіт["крамниця"] = dict(пул_рук=готовий, чому=чому,
                                кандидатів={с: len(р) for с, р in пули.items()})
        for ціль in цілі:
            сл = за_ід[ціль]["слот"]
            кандидати = []
            for r in пули.get(сл) or []:
                if not r.get("lab") or not r.get("id"):
                    continue
                ч = _РФ.членство_в_палітрі(r["lab"], палітра)
                if ч["стан"] != "у палітрі":
                    continue
                кандидати.append((ч["сила"], r))
            кандидати.sort(key=lambda х: -х[0])
            for _с, r in кандидати[:КРАМНИЦЯ_НА_ЦІЛЬ]:
                с = _спроба(ціль, r["id"], r.get("слот") or сл, dict(r), "shop")
                if с:
                    крамні.append(с)
    свої.sort(key=lambda с: с["дельта"])
    крамні.sort(key=lambda с: с["дельта"])
    обрані, бачено = [], set()
    for с in свої + крамні:
        if (с["ціль"], с["нова"]) in бачено:
            continue
        бачено.add((с["ціль"], с["нова"]))
        обрані.append(с)
        if len(обрані) >= ЗМІН_МАКС:
            break
    for н, с in enumerate(обрані):
        с["ід"] = "з%d" % (н + 1)
    крамні_ід = [с["нова"] for с in обрані if с["звідки"] == "shop"]
    if крамні_ід:
        звіт["вітрина"] = вітрина(d, крамні_ід)
        for с in обрані:
            if с["звідки"] == "shop":
                с["річ"] = звіт["вітрина"].get(с["нова"]) or {}
    return обрані, звіт


