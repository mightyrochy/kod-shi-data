def _виміри_кроками(речі, пікселі, пікселі_фото, шкіра):
    """Міряє ділянку речі; перенос на інше фото зберігає її ід.

    `пікселі` — {ід речі: кадр її рамки на її фото}; `пікселі_фото` — {ід речі: {ід фото: кадр
    тієї самої рамки на іншому фото}}. Перенос лишає `фото_моделі` для запису ходу;
    ід позначає екземпляр, фото й рамка — його поточне місце.

    Генератор (`yield` після кожної речі й усередині виміру кольору — `річ_з_фото.виміряти_кроками`): див. `_ганяти`."""
    вих, лічба = [], {}
    for р in речі or []:
        if isinstance(р, dict) and р.get("ід"):
            лічба[р.get("фото")] = лічба.get(р.get("фото"), 0) + 1
    for р in речі or []:
        if not isinstance(р, dict) or not р.get("ід"):
            continue
        р = dict(р)
        # БЕЗ РАМКИ — НЕ КАДР ЧУЖИХ РЕЧЕЙ (п.18): показ без рамки ріже ціле фото, і на фото з кількома
        # речами вимір брав переважний колір кадру — светр хакі й бордові штани ф1 обидва #82896e
        # (хакі), «бордове» йшло в суд хакі. Колір речі — вимір, коли маска певна, а маски однієї речі на кадрі
        # кількох нема. Без рамки міряється лише річ, сама на своєму фото; інакше — слово стилістки, без `lab`.
        if р.get("дотик") and пікселі.get(р["ід"]):
            # ЇЇ ДОТИК ПО ФОТО: вікно навколо нього — сама річ, тла в ньому не шукають
            р["вимір"] = _РФ.виміряти_дотик(пікселі[р["ід"]], слово_моделі=р.get("колір"), шкіра_hex=шкіра)
        elif пікселі.get(р["ід"]) and (р.get("рамка") or лічба.get(р.get("фото")) == 1):
            р["вимір"] = yield from _РФ.виміряти_кроками(пікселі[р["ід"]], слово_моделі=р.get("колір"),
                                                          шкіра_hex=шкіра, рамка=р.get("рамка"))
        # ЇЇ ДОТИК — КЛЮЧ ЕКЗЕМПЛЯРА (наряд 6.2): фото й місце показала вона, тож річ не переноситься на інше фото. Кадри
        # `пікселі_фото` — рамка МОДЕЛІ на інших фото, різана до її правки: спір її дотику зі словом моделі переносив би
        # річ туди, куди вказала модель, а не вона
        if (р.get("вимір") or {}).get("спір") and пікселі_фото.get(р["ід"]) and not р.get("колір_її") \
                and not р.get("дотик"):
            кадри = {ф: п for ф, п in пікселі_фото[р["ід"]].items() if ф != р.get("фото")}
            ф, вим = yield from _РФ.фото_за_словом_кроками(кадри, р.get("колір"), шкіра_hex=шкіра,
                                                           рамка=р.get("рамка"))
            if ф:
                р["фото_моделі"] = р["фото"]
                _місце_речі(р, ф, р.get("рамка"))
                р["вимір"] = вим
        вих.append(р)
        yield
    return вих


