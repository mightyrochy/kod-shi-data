#   · «frame» — колір міряє код пікселями в межах рамки (`річ_з_фото.виміряти`), тож рамка
#     мусить обіймати саму річ, без тла й шкіри;
#   · одна річ на кількох фото — один запис: інакше образ мав би дві однакові сукні, і
