# ── СУД НЕ ЧЕКАЄ КАТАЛОГУ, ЯКОГО НЕ ВЖИВАЄ ──────────────────────────────────────────────────
# ЩО БУЛО. Показ кликав суд лише після кінця прогріву каталогу: без нагоди суд стартував на 11,4–12,3 с, з «Робота» — на
# 19,4–19,5 с (проба 5770), картка — 17,2–23,5 с; 65–83 % цього часу — каталог у Pyodide, а вердикт образу каталогу не
# вживає зовсім: його потребує лише крок «крамниця» змін (пул рук, бюджет, вітрина).
# ЩО ТЕПЕР. Суд іде одразу за переліком, у тому самому циклі Pyodide, що й прогрів. Поки суд рахує сам, прогрів стоїть
# (потік один, і вердикт — першим); дійшовши до кроку «крамниця», суд віддає йому потік і чекає його кінця — далі той
# самий теплий каталог, що й доти, тож вердикт і зміни ті самі. Синхронні `суд`/`прогріти_каталог` цього не знають.
# ── КРАМНИЦЯ ЧЕКАЄ КАТАЛОГУ, А НЕ ПОКАЖЧИКІВ ВІТРИНИ ───────────────────────────────────────────────
# ЩО БУЛО. Прогрів кінчався покажчиками вітрини (≈ 3,5 с у Pyodide), і крок «крамниця» чекав їх, хоч читає їх лише
# `вітрина` — і лише тоді, коли зміна з крамниці є (з «Робота» на пробі 5770 змін 0, а картка чекала 3,7 с).
# ЩО ТЕПЕР. Прогрів віддає результат на кінці каталогу (`_КАТАЛОГ_ГОТОВИЙ`): крок «крамниця» йде далі, звіт має
# `етапи.каталог`. Покажчики добудовує фонове завдання (`_покажчики_без_блоку`), поки суду нема; суд, якому вітрина
# потрібна, чекає його кінця (`_КРОК_ВІТРИНА`), а скінчений без вітрини суд його зупиняє — тоді картці покажчики вже не
# потрібні, і їх не будує ніхто (вітрина наступного суду добудує їх шматками сама, `_покажчики_вітрини_кроками`).
_КРОК_КРАМНИЦЯ = object()            # `yield` кроку «крамниця» в `зміни_кроками`: далі потрібен каталог
_КРОК_ВІТРИНА = object()             # `yield` перед `вітрина` в `зміни_кроками`: далі потрібні покажчики вітрини
_КАТАЛОГ_ГОТОВИЙ = object()          # `yield (_КАТАЛОГ_ГОТОВИЙ, результат)` прогріву між каталогом і покажчиками
_ЦИКЛ = {"прогрів": 0, "вітрина": 0, "суд": 0, "суд_чекає": 0, "судів": 0}
_ФОНОВІ = set()                      # завдання покажчиків: посилання, щоб цикл подій їх не загубив


async def прогріти_каталог_без_блоку(d):
    """`прогріти_каталог_кроками` у Pyodide: між кроками — `asyncio.sleep(0)`, тобто хід головному потоку сторінки
    (екран «Роздивляюсь речі…» не відповідав на прокрутку й вкладки 10–15 с), і пауза, поки суд рахує
    вердикт. Результат — на кінці каталогу; покажчики вітрини далі — фоном."""
    г, слід = прогріти_каталог_кроками(d), _СЛ.свій_слід()    # слід — свій на весь прогрів
    _ЦИКЛ["прогрів"] += 1
    try:
        while True:
            к = _СЛ.у_своєму(слід, next, г)
            if isinstance(к, tuple) and к and к[0] is _КАТАЛОГ_ГОТОВИЙ:
                з = _asyncio.ensure_future(_покажчики_без_блоку(г, слід))
                _ФОНОВІ.add(з)
                з.add_done_callback(_ФОНОВІ.discard)
                return к[1]
            await _asyncio.sleep(0)
            while _ЦИКЛ["суд"] > _ЦИКЛ["суд_чекає"]:
                await _asyncio.sleep(0.01)
    except StopIteration as к:
        return к.value
    finally:
        _ЦИКЛ["прогрів"] -= 1


async def _покажчики_без_блоку(г, слід):
    """Решта прогріву (покажчики вітрини) фоном: стоїть, поки суд рахує сам; кінчається, коли суд скінчився без
    вітрини. `слід` — той самий власний слід прогріву."""
    судів = _ЦИКЛ["судів"]
    _ЦИКЛ["вітрина"] += 1
    try:
        while True:
            try:
                _СЛ.у_своєму(слід, next, г)
            except StopIteration:
                return
            await _asyncio.sleep(0)
            while _ЦИКЛ["суд"] > _ЦИКЛ["суд_чекає"]:
                await _asyncio.sleep(0.01)
            if _ЦИКЛ["судів"] != судів:
                return
    finally:
        _ЦИКЛ["вітрина"] -= 1
        _СЛ.у_своєму(слід, г.close)


def _покажчики_вітрини_кроками(d):
    """Покажчики вітрини (`міст_опис.показ`: офери, кольори кадрів, папки товарів — раз на файл, ≈ 3,5 с у Pyodide
    першим разом) шматками; далі `вітрина` бере їх із кеша. Каталогу нема — нічого."""
    if not d.get("каталог"):
        return
    yield from _МОП.контекст_кадрів_кроками(_МП.каталог_із(d)[0])


def прогріти_каталог_кроками(d):
    """Каталог піднімається, поки модель дивиться на фото (показ кличе цей крок одразу після
    виклику `РЕЧІ`): `feed.прогін` кешує себе сам, і крок «суд» бере вже теплий каталог.

    Генератор (див. `_ганяти`): розбір фіду (50 МБ XML, 12 тис. оферів), розпаковка таблиці каталогу, відновлення
    бази, покриття вікон і покажчики вітрини йдуть шматками, між якими потік вільний. Між каталогом і
    покажчиками — `yield (_КАТАЛОГ_ГОТОВИЙ, результат)`: далі результат той самий."""
    if not d.get("каталог"):
        return dict(готово=False, чому="no_catalog")
    F, T, dd = профіль(d)
    сц, _звідки = сценарій_оцінки(d.get("сценарій_оцінки"), d.get("сценарій_слів"), d.get("сценарій_паспорта"),
                                        плитки=d.get("сценарій_плитки"))
    сцен, _н = _сцена(сц, dd)
    yield
    try:
        _пули, чому, готовий, пак = yield from _крамниця_кроками(dd, F, T, сцен, [])
    except (KeyError, TypeError, ValueError) as е:
        # П.14: чужий вхід (каталог не той, профіль без обхватів) — прогрів лише пришвидшує,
        # і його провал оцінки не зупиняє: крок «суд» назве ту саму причину своїм полем
        return dict(готово=False, чому="%s: %s" % (type(е).__name__, е))
    вих = dict(готово=bool(готовий), чому=чому, речей=len(пак.get("_каталог") or []))
    yield (_КАТАЛОГ_ГОТОВИЙ, вих)
    # Покажчики — тут, поки модель дивиться на фото, а не в кінці суду: там жінка вже тисне «Так, оцінюй», і сторінка
    # не чула б дотику
    try:
        yield from _покажчики_вітрини_кроками(dd)
    except (KeyError, TypeError, ValueError):
        pass
    return вих


def _сцена(сценарій, d):
    """Сцена суду — ЛИШЕ те, що вона назвала (екран або її слова), і намір; без типових полів."""
    сцен, незн = _ПН.з_показу({к: v for к, v in (сценарій or {}).items() if v not in (None, "")}, None)
    if d.get("самозвіт"):
        сцен["самозвіт"] = _МВ.самозвіт(d)
    сцен.setdefault("intent", d.get("намір") or "conventional")
    return сцен, незн


def профіль(d):
    """Вхід показу → (F, T, d): риси, тіло й нормалізований вхід (драпіровка → самозвіт)."""
    d = _МВ.нормалізувати_вхід(dict(d, сценарій={}))
    F, T, _зріст, _kw = _МВ.збірка(d)
    return F, T, d


def _ваги_образу(ід, записи, F, T, сцен, драп):
    """Суд образу з цих записів тим самим судом, що й образи рук → вихід `перевірити_від_моделі`."""
