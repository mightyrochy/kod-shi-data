"""ЗВІРКА ЗБАГАЧЕННЯ — чи бачить модель на фото той колір, який назвала крамниця.

Вибірка: 200 випадкових речей (сід 17) з описом з фото і з param «Колір», у якому
`verify.назва_кольору` знаходить слово ЛЕКСИКОНУ. Порівняння трьома щаблями:
  · слово      — те саме слово ЛЕКСИКОНУ;
  · сім'я тону — `СІМ_Ї_СЛІВ`: 12 груп слів ЛЕКСИКОНУ (світла нейтраль,
                 беж/кемел, сіра, чорна, коричнева, червона, розова, помаранчева,
                 жовта, зелена, синя, фіолетова);
  · будь-яке   — слово моделі збігається за сім'єю з БУДЬ-ЯКИМ словом крамниці
                 («білий темносиній» — модель мала право побачити будь-який).
20 розбіжностей за сім'єю (з першим словом) виписуються для ока: id, тип, слово
крамниці, слово й hex моделі, її опис, фото.

Запуск:  python3 звірка_збагачення.py [--n 200] [--вибірка 20]
Звіт:    аудит/ЗБАГАЧЕННЯ_ЗВІТ.md
"""
import argparse, collections, gzip, math, os, random, re, sys, time

ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ТУТ)
import feed as F
import verify as V

ЗВІТ = os.path.join(ТУТ, "аудит", "ЗБАГАЧЕННЯ_ЗВІТ.md")


# Сім'ї — за СЛОВАМИ ЛЕКСИКОНУ, а не за дугою центру вікна: перша версія клала
# «молочний», «бежевий», «кемел» у жовту дугу (центр h≈75–82°, C*≈11–27), і
# «молочна сукня» проти «білої» рахувалась розбіжністю тону, хоча для ока і для
# палітри це одна світла нейтраль.
СІМ_Ї_СЛІВ = {
    "світла нейтраль": ("білий", "молочний", "вершковий"),
    "беж / кемел": ("бежевий", "пісочний", "кемел"),
    "сіра": ("сірий", "срібний", "графіт"),
    "чорна": ("чорний",),
    "коричнева": ("коричневий", "шоколадний"),
    "червона": ("червоний", "бордовий", "вишневий"),
    "розова": ("рожевий", "пудровий", "персиковий"),
    "помаранчева": ("помаранчевий", "теракотовий"),
    "жовта": ("жовтий", "лимонний", "гірчичний", "золотий"),
    "зелена": ("зелений", "оливковий", "хакі", "м'ятний"),
    "синя": ("синій", "темно-синій", "блакитний", "бірюзовий"),
    "фіолетова": ("фіолетовий", "бузковий"),
}
_СІМ_Я = {с: ім for ім, сл in СІМ_Ї_СЛІВ.items() for с in сл}
assert set(_СІМ_Я) == set(V.ЛЕКСИКОН), set(V.ЛЕКСИКОН) ^ set(_СІМ_Я)


def сім_я_слова(слово):
    return _СІМ_Я.get(слово)


def слова_крамниці(сирий):
    """Усі слова ЛЕКСИКОНУ, які стоять у param «Колір», у порядку появи."""
    вих = []
    for частина in F._СЕП_КОЛЬОРУ.split(сирий or ""):
        с = V.назва_кольору(частина)
        if с and с not in вих:
            вих.append(с)
    return вих


def пакет_руки_1(вхід=os.path.join(ТУТ, "стенд_вх.json")):
    """Частка речей ПУЛУ руки 1, чий колір бачено на фото. Той самий шлях, що
    стенд: `bridge.виклик("запити", стенд_вх)`; рука 1 = `кандидати`, а
    `колір_джерело` береться з каталогу цього ж пакета за id (рядок пулу для
    моделі свідомо не несе провенансу)."""
    import json as _j
    import bridge as B
    тут = os.getcwd()
    os.chdir(ТУТ)                      # стенд_вх називає каталог і кеш відносно джерела/
    try:
        r = _j.loads(B.виклик("запити", open(вхід, encoding="utf-8").read()))
        кат = {c.get("id"): c for c in B.каталог_останнього_пакета()}
    finally:
        os.chdir(тут)
    ід = [x.get("id") for рч in (r.get("кандидати") or {}).values() for x in рч]
    за = collections.Counter((кат.get(i) or {}).get("колір_джерело") for i in ід)
    n = len(ід)
    return dict(речей=n, за_джерелом=dict(за), фото=за.get("фото", 0),
                частка=(за.get("фото", 0) / n if n else 0.0), помилка=r.get("помилка"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=200)
    ap.add_argument("--вибірка", type=int, default=20)
    ap.add_argument("--лог", default=os.path.join(ТУТ, "жнива_лог.txt"))
    ap.add_argument("--без-пакета", action="store_true", help="не проганяти bridge на стенд_вх.json")
    а = ap.parse_args()

    with gzip.open(os.path.join(ТУТ, "..", "каталог_повний.xml.gz"), "rb") as f:
        offers, _ = F.читати_yml(f)
    за_id = {o["id"]: o for o in offers}
    зб = F.читати_збагачення()
    описані = {k: v for k, v in зб.items() if F._збагачення_придатне(v)}

    # ── покриття полів на всьому файлі ──
    n_усіх, n_зб = len(offers), len(зб)
    помилки = sum(1 for v in зб.values() if "помилка" in v)
    # МЕЖА БЕРЕТЬСЯ З КОДУ, А НЕ ПОВТОРЮЄТЬСЯ ТУТ ЧИСЛОМ: `feed.ЗБАГАЧЕННЯ_ПОРІГ`
    # вирішує, коли опис перекриває слово крамниці, і звіт мусить рахувати ту саму
    # межу — інакше між «придатний» і «не видно» лишиться мовчазна щілина.
    не_видно = sum(1 for v in зб.values() if "помилка" not in v
                   and (v.get("впевненість") or 0) < F.ЗБАГАЧЕННЯ_ПОРІГ)
    інше = len(зб) - len(описані) - помилки - не_видно
    за_чим = collections.Counter(F.колір_збагачення(v)[2] for v in описані.values())
    поле = lambda ім: sum(1 for v in описані.values() if v.get(ім) not in (None, ""))
    розп = lambda ім, n=8: collections.Counter(v.get(ім) for v in описані.values()).most_common(n)
    друге_фото = sum(1 for v in описані.values() if v.get("фото_номер") == 2)

    # ── вибірка ──
    придатні = []
    for k, v in описані.items():
        o = за_id.get(k)
        if not o:
            continue
        сл = слова_крамниці(o.get("колір_сирий"))
        if сл:
            придатні.append((k, v, o, сл))
    random.Random(17).shuffle(придатні)
    виб = придатні[:а.n]
    точно = родина = будь = 0
    розбіжні = []
    матриця = collections.Counter()
    for k, v, o, сл in виб:
        м = F.колір_збагачення(v)[0]
        с_м, с_к = сім_я_слова(м), сім_я_слова(сл[0])
        точно += м == сл[0]
        родина += с_м == с_к
        будь += any(сім_я_слова(x) == с_м for x in сл)
        if с_м != с_к:
            матриця[(с_к, с_м)] += 1
            розбіжні.append((k, v, o, сл, с_к, с_м))
    N = len(виб) or 1

    # ── швидкість з логу жнив ──
    швидкість = []
    if os.path.exists(а.лог):
        for р in open(а.лог, encoding="utf-8"):
            if "реч/с" in р:
                швидкість.append(р.strip())

    Р = []
    w = Р.append
    w("# Збагачення каталогу з фото — звіт")
    w("")
    w("Згенеровано `звірка_збагачення.py` %s. Модель: %s (LM Studio, локально), фото стиснуте до 512 px, "
      "відповідь обмежена JSON-схемою зі словниками правил." % (
          time.strftime("%Y-%m-%d %H:%M"), next((v.get("модель") for v in описані.values()), "?")))
    w("")
    w("## Покриття")
    w("")
    w("| | речей | частка |")
    w("|---|---:|---:|")
    w("| офери каталогу | %d | 100 %% |" % n_усіх)
    w("| мають запис у `каталог_збагачення` | %d | %.1f %% |" % (n_зб, 100 * n_зб / n_усіх))
    w("| придатний опис (колір є, річ видно) | %d | %.1f %% |" % (len(описані), 100 * len(описані) / n_усіх))
    w("| помилка (фото не скачалось / сервер) | %d | %.1f %% |" % (помилки, 100 * помилки / n_усіх))
    w("| «речі не видно» (логотип, таблиця — впевненість < %.1f) | %d | %.1f %% |"
      % (F.ЗБАГАЧЕННЯ_ПОРІГ, не_видно, 100 * не_видно / n_усіх))
    w("| решта непридатних (слово кольору поза ЛЕКСИКОНОМ) | %d | %.1f %% |" % (інше, 100 * інше / n_усіх))
    w("| опис з ДРУГОГО фото | %d | %.1f %% описаних |" % (друге_фото, 100 * друге_фото / max(1, len(описані))))
    for зч, c in за_чим.most_common():
        w("| точка кольору: %s | %d | %.1f %% описаних |" % (зч, c, 100 * c / max(1, len(описані))))
    w("")
    w("Поля в описаних речах (null = модель сказала «не видно / не застосовно»):")
    w("")
    w("| поле | заповнено | найчастіші значення |")
    w("|---|---:|---|")
    for ім in ("колір_другий", "матеріал", "крій", "довжина", "блиск", "візерунок", "формальність"):
        w("| %s | %.1f %% | %s |" % (ім, 100 * поле(ім) / max(1, len(описані)),
                                   ", ".join("%s %d" % (("—" if x is None else (x["слово"] if isinstance(x, dict) else x)), c)
                                             for x, c in (розп(ім) if ім != "колір_другий" else
                                                          collections.Counter((v.get(ім) or {}).get("слово") for v in описані.values()).most_common(6)))))
    w("")
    w("## Колір: модель проти слова крамниці (вибірка %d)" % len(виб))
    w("")
    w("Вибірка з %d речей, де param «Колір» дає слово ЛЕКСИКОНУ; сід 17." % len(придатні))
    w("")
    w("| щабель | збіг | частка |")
    w("|---|---:|---:|")
    w("| те саме слово | %d | %.1f %% |" % (точно, 100 * точно / N))
    w("| та сама сім'я тону (перше слово крамниці) | %d | %.1f %% |" % (родина, 100 * родина / N))
    w("| сім'я збігається з БУДЬ-ЯКИМ словом крамниці | %d | %.1f %% |" % (будь, 100 * будь / N))
    w("")
    w("Найчастіші розбіжності за сім'єю (крамниця → модель):")
    w("")
    for (к, м), c in матриця.most_common(10):
        w("- %s → %s: %d" % (к, м, c))
    w("")
    w("## %d розбіжностей для ока" % min(а.вибірка, len(розбіжні)))
    w("")
    w("| # | id | тип | крамниця | модель | hex | опис моделі | фото |")
    w("|---:|---|---|---|---|---|---|---|")
    for i, (k, v, o, сл, с_к, с_м) in enumerate(розбіжні[:а.вибірка], 1):
        к = v["колір_основний"]
        w("| %d | `%s` | %s | %s (%s) | %s (%s) | `%s` | %s | [фото](%s) |" % (
            i, k, v.get("тип_запиту") or "", o.get("колір_сирий"), с_к, F.колір_збагачення(v)[0], с_м, к.get("hex"),
            (v.get("опис") or "").replace("|", "/")[:160], v.get("фото")))
    w("")
    w("## Пакет руки 1 (`bridge.виклик('запити', стенд_вх.json)`)")
    w("")
    if а.без_пакета:
        w("Не проганявся (`--без-пакета`).")
    else:
        п = пакет_руки_1()
        w("Речей у пулі руки 1: **%d**; колір з фото: **%d** (**%.1f %%**). За джерелом: %s." % (
            п["речей"], п["фото"], 100 * п["частка"],
            ", ".join("%s %d" % (k or "—", v) for k, v in sorted(п["за_джерелом"].items(), key=lambda x: -x[1]))))
        if п["помилка"]:
            w("")
            w("Помилка моста: %s" % п["помилка"])
        print("пакет руки 1: %d речей, з фото %d (%.1f %%)" % (п["речей"], п["фото"], 100 * п["частка"]))
    w("")
    w("## Швидкість жнив")
    w("")
    if швидкість:
        w("```")
        for р in (швидкість[:2] + ["…"] + швидкість[-3:] if len(швидкість) > 6 else швидкість):
            w(р)
        w("```")
    else:
        w("Лог жнив не знайдено.")
    w("")
    os.makedirs(os.path.dirname(ЗВІТ), exist_ok=True)
    open(ЗВІТ, "w", encoding="utf-8").write("\n".join(Р))
    print("\n".join(Р[:40]))
    print("… звіт: %s" % ЗВІТ)


if __name__ == "__main__":
    main()
