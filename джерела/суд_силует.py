def мономісце(речі, _E):
    """K-SIL-09: сукня (або одна річ) фіксує верх, низ і силует одночасно.

    ВХІД — СЛОТ, А НЕ ПЛОЩА. Корпус: «WHEN: the outfit's only major surface is a
    dress (or a single garment)». `_E` зберігає сигнатуру сім'ї: колірні
    елементи для пояснення моно-об'єкта не потрібні. Одна поверхня — факт слота, і
    рахувати його через виміряну частку площі означало б поставити правилу вхід,
    якого воно не просить (і якого фід не дає)."""
    # КОМПЛЕКТ — ДВІ ЧАСТИНИ, НЕ ОДНА (СУД-974). Слот «комплект» (піджак +
    # палаццо, костюм-двійка) — це верх і низ, що йдуть однією карткою; він НЕ фіксує
    # верх, низ і силует «одним предметом», а має два силуети (його `fit` не ділить на
    # талії саме тому). Раніше він стояв у «сукня» й суд писав про «Костюм піджак
    # однобортний та палаццо пісок»: «сукня — моно-об'єкт» (весілля В, per_536).
    # Правило лишається лише для сукні й цільної речі: образ із комплектом — не моно.
    if any(р.get("слот") == "комплект" for р in речі):
        return []
    поверхні = [р for р in речі if р.get("слот") in ПОВЕРХНІ_ОБРАЗУ]
    if len(поверхні) != 1:
        return []
    р = поверхні[0]
    сукня = (р.get("слот") == "сукня")
    назва = р.get("назва") or р.get("id")
    кр = крій_речі(р)
    сем = СЕМАНТИКА_СУКНІ.get(кр)
    # K-CRA-01 рахує шар чи аксесуар понад базою; тут сама поверхня одна, тобто
    # верх, низ і силует вирішені однією річчю, і задача звелась до взуття, шару
    # й аксесуарів. Два різні твердження про один образ, і обидва з корпусу.
    return [dict(_зн(
        "K-SIL-09", "soft",
        "%s — моно-об'єкт силуету: образ одягнений, не стилізований"
        % ("сукня" if сукня else "одна річ"),
        [назва],
        ("сукня фіксує верх, низ і силует одночасно; задача зводиться до взуття + "
         "шару + аксесуарів, і без них образ читається як «одягнена», не "
         "«стилізована» (тема-4 PART V)" if сукня else
         "єдина гардеробна поверхня образу вирішує і верх, і низ, і силует") +
        ("; крій «%s» — %s" % (кр, сем) if сем else ""),
        ламається="сила — конвенція практиків (T3), не вимір; свідомий мінімалізм і "
                  "сувора уніформа роблять моно-об'єкт ходом, а не діагнозом. У фіді "
                  "без взуття й шарів рядок однаковий на всіх сукнях: він міняє ТЕКСТ "
                  "людині, не ранг",
        поріг=2.0, вимір=1.0, повна=2.0,
        заяви=[_ВМ.заява("mono_object_silhouette", dress=сукня)]),
        сила_нп=0.5, сила_нп_джерело="категорія (одна гардеробна поверхня в образі)")]


# ── K-SIL-10: КАРТА СПІДНИЦЬ ─────────────────────────────────────────────────
# Корпус дає карту читань і ОДНЕ твердження з наслідком: «midi is the riskiest
# length: the termination point is critical (narrowest point of the calf) and the
# shoe decides the proportion»; «maxi (needs height, lift, or deliberate volume)».
# ВХІД ВИМІРЯНО (`каталог_повний`): спідниць 631, з них 424 несуть
# `довжина_рівень` (литка 200, максі 115, міні 103, коліно 5, стегно 1) і 180 —
# канонічний `крій`. Каблук у сантиметрах несуть 1 136 пар із 1 898.
# ЩО САМЕ ВИХОДИТЬ ЗНАХІДКОЮ, А ЩО НІ:
#   максі без підйому — знахідка з УМОВОЮ: правило саме називає три способи
#     («height, lift, or deliberate volume»), і два з них вимірні — каблук пари в
#     образі й об'ємний крій самої спідниці. Коли обидва відсутні, сказано це;
#   міді — `hint`: рядок називає ту річ, яка вирішує пропорцію (взуття), і не
#     вдає, що знає відповідь: точка завершення в сантиметрах у фіді відсутня
#     (`довжина_рівень` — рівень тіла, не см), тож «найвужча точка литки» тут не
#     перевіряється й це сказано в «ламається»;
#   міні — НЕ виходить: «legs become the focus» уже судить K-KOH-10 (одна
#     відкрита зона), і другий рядок про те саме був би тим самим дублем кодів,
#     від якого сім'я силуету вже відмовилась (`_форма_не_читається`).
ОБ_ЄМНІ_КРОЇ_СПІДНИЦІ = ("a-line", "full", "pleated", "flared")
КАРТА_СПІДНИЦЬ = {
 "pencil":  "олівець: структура, формальність, X/H",
 "a-line":  "A-силует: універсальна, балансує A",
 "pleated": "плісе: об'єм і рух, дружня до V",
 "full":    "вільна: об'єм, потребує якоря",
 "flared":  "кльош: рух від коліна",
 "straight":"пряма: рівна лінія, без власного об'єму",
}

def карта_спідниць(речі):
    """K-SIL-10. Спідниця в образі читається за картою корпусу; наслідок мають
    два її рядки — максі без підйому й міді, чию пропорцію вирішує взуття."""
    зн = []
    спідниці = [р for р in речі
                if р.get("слот") == "низ" and str(р.get("тип") or "") == "спідниця"]
    if not спідниці:
        return зн
    взуття = [р for р in речі if р.get("слот") == "взуття"]
    каблуки = [float(р["каблук_см"]) for р in взуття if р.get("каблук_см") is not None]
    каблук = max(каблуки) if каблуки else None      # None = картка мовчить, не «0 см»
    # Смуга крамниці («від 4 до 6 см») доводить нижній край: пара не нижча.
    підлоги = [в for в in map(висота_або_підлога, взуття) if в is not None]
    підлога = max(підлоги) if підлоги else None
    for с in спідниці:
        рівень = с.get("довжина_рівень")
        кр = крій_речі(с)
        назва = с.get("назва") or с.get("id")
        читання = КАРТА_СПІДНИЦЬ.get(кр)
        if рівень == "максі":
            обʼємна = кр in ОБ_ЄМНІ_КРОЇ_СПІДНИЦІ
            підйом = (підлога if підлога is not None else 0.0)
            if обʼємна or (підлога is not None and підлога >= 4.0):
                continue                      # спосіб із трьох названих у корпусі — є
            зн.append(dict(_зн(
                "K-SIL-10", "default",
                "максі без підйому й без власного об'єму", [назва],
                "корпус дає максі рівно три опори — зріст, підйом або свідомий об'єм. "
                "Крій %s, каблук у парі %s: жодної з трьох у цьому образі нема"
                % ("«%s» об'єму не будує" % кр if кр else "не названий",
                   ("%.1f см" % каблук) if каблук is not None else
                   "не названий карткою"),
                заяви=[_ВМ.заява("maxi_without_lift_or_volume",
                                 **({"heel_cm": round(каблук, 1)} if каблук is not None else {}))],
                ламається="«зріст» третьою опорою тут не рахується: поріг зросту, з "
                          "якого максі тримається без підйому, корпус не дає, а "
                          "вигадати його означало б зробити з конвенції вимір. Каблук "
                          "несуть 1 136 пар із 1 898 — де картка мовчить, правило "
                          "бачить рівно те, що бачить жінка на фото",
                поріг=4.0, вимір=float(підйом), повна=4.0),
                сила_нп=0.5,
                сила_нп_джерело="категорія (жодної з трьох опор максі в образі)"))
        elif рівень == "литка":
            зн.append(dict(_зн(
                "K-SIL-10", "hint",
                "міді — найризикованіша довжина, і пропорцію вирішує взуття", [назва],
                # R-LNG-01 забороняє судити ефект на тілі без мети людини;
                # Тому твердження про довжину ноги тут не робиться.
                # Те, що правило справді міряє, — стик двох речей: поділу й пари.
                "поділ закінчується на литці, і саме точка завершення вирішує "
                "пропорцію між поділом і парою. %s%s"
                % ("Читання крою: %s. " % читання if читання else "",
                   ("Пара в образі — каблук %.1f см" % каблук) if каблук is not None
                   else "Каблука пари картка не називає"),
                заяви=[_ВМ.заява("midi_proportion_decided_by_shoes",
                                 **({"heel_cm": round(каблук, 1)} if каблук is not None else {}))],
                ламається="«найвужча точка литки» тут НЕ перевіряється: фід несе рівень "
                          "тіла («литка»), а не точку завершення в сантиметрах, тож "
                          "правило називає ризик і того, хто його вирішує, і не вдає, "
                          "що знає відповідь. Сила — hint саме тому",
                поріг=0.0, вимір=1.0, повна=2.0),
                сила_нп=0.2, сила_нп_джерело="категорія (довжина «литка» без точки завершення)"))
    return зн


def силует_образу(речі, E, _intent=ТИПОВИЙ_НАМІР):
    """Сім'я силуету над ЗІБРАНИМ образом: K-SIL-09 + K-SIL-10. Один вхід.

    `_intent` НЕ ЧИТАЄТЬСЯ СВІДОМО: сигнатура одна на входи суду, які кличе конвеєр,
    але обидва правила — про МІСЦЕ (одна річ на місце) і карту спідниць; намір не
    робить друге кольє на тій самій шиї доречним."""
    зн = мономісце(речі, E) + карта_спідниць(речі)
    return [z for z in обмежити_вагу(зн) if not z.pop("під_підлогою", False)]
# ── K-SIL-06: ВІДПОВІДНІСТЬ МАСШТАБІВ ──────────────────────────────────────
# Корпус: «розмір принта, маса аксесуарів, фактурність ∝ масштаб особи». [C·strong]
#
# МАСШТАБ ОСОБИ — не зріст. Береться як обхват зап'ястя відносно зросту, коли він є
# (кістяк), інакше — зріст як груба заміна, і це ПОЗНАЧАЄТЬСЯ.
# МАСШТАБ ПРИНТА вже ВИМІРЮЄТЬСЯ: `feed._просторові_міри` дає `масштаб_відн` —
# медіанну довжину пробігу мотиву як частку кадру. Тобто правило має реальний вхід і
# не потребує нового поля.
#
# ⚠ ЦЕ НАЙСЛАБША З РЕАЛІЗОВАНИХ ТУТ: «∝» у корпусі не має ні коефіцієнта, ні
# виміряного порогу, а зв'язок масштаб-особи ↔ масштаб-принта не міряв ніхто з
# процитованих. Тому правило не судить: виміряне йде моделі фактом «утримано» (`масштаби`).
# Вікно відношення зап'ястя/зріст. ФОЛЬКЛОРНІ константи: джерела для «масштабу особи»
# корпус не дає взагалі («∝» без коефіцієнта). Числа поставлені так, щоб реальний
# жіночий діапазон (зап'ястя 14–18 см, зріст 155–175) лягав усередину 0..1, а не
# сплющувався в край. K-SIL-06 їх більше не читає (`масштаби`); лишились для `масштаб_особи`
# у звіті `run_outfit`.
ЗАПʼЯСТЯ_ЦЕНТР = 0.095
ЗАПʼЯСТЯ_ПІВ = 0.018

def масштаб_особи(тіло):
    """(значення 0..1, джерело). 0 = дрібний кістяк, 1 = великий."""
    if not тіло: return None, "тіла нема"
    о = (тіло.get("обхвати") or {})
    з = тіло.get("зріст")
    if о.get("зап'ястя") and з:
        # ⚠ ПЕРЕКАЛІБРОВАНО ПІСЛЯ ТОГО, ЯК ГІЛКА СТАЛА ДОСЯЖНОЮ. Перші константи
        # (центр 0.105, вікно ±0.15 відносних) я поставив НАОСЛІП — гілка тоді падала
        # ValueError у `посадка.тіло`, тож перевірити їх було неможливо. Щойно вона
        # запрацювала, прогін показав: увесь звичайний жіночий діапазон зап'ястя
        # 13.5–16 см на зрості 168 давав масштаб РІВНО 0.00, тобто «дрібний кістяк»
        # для всіх, і правило не розрізняло нічого. Це урок ширший за цю функцію:
        # константа за недосяжною гілкою не має жодного захисту від помилки.
        # Тепер вікно накриває реальний діапазон: зап'ястя 14–18 см на зрості
        # 155–175 дає відношення приблизно 0.080–0.116.
        v = float(о["зап'ястя"]) / float(з)
        return (max(0.0, min(1.0, (v - ЗАПʼЯСТЯ_ЦЕНТР + ЗАПʼЯСТЯ_ПІВ)
                             / (2 * ЗАПʼЯСТЯ_ПІВ))),
                "обхват зап'ястя / зріст = %.4f (кістяк)" % v)
    if з:
        return max(0.0, min(1.0, (float(з) - 152.0) / 30.0)), \
               ("ЗРІСТ як груба заміна кістяка — обхвату зап'ястя нема. Зріст і кістяк "
                "корелюють слабко: висока тонкокістна жінка дістане завищений масштаб")
    return None, "ні зап'ястя, ні зросту"

def масштаби(E, тіло=None):
    """K-SIL-06. Масштаб мотиву і масштаб особи — фактом моделі, без судження коду.

    Тут стояло порівняння двох нормованих чисел: масштаб мотиву (частка кадру / 0.35) проти
    масштабу особи (зап'ястя / зріст у вікні ЗАПʼЯСТЯ_ЦЕНТР ± ЗАПʼЯСТЯ_ПІВ, без зап'ястя —
    сам зріст), з допуском 0.35, і код називав бік — «більший» чи «дрібніший». Це різні
    величини (частка кадру фото проти кістяка тіла), зведені фольклорними константами, і
    похибки жодного боку код не знає: різниця оцінок двох різних величин — не факт
    (Е3-одна-величина, рішення 06.11 «факт замість межі», п.3). Бік і різницю порівняння код
    називає лише понад похибку обох боків, а річ порівнює лише з виміром тієї самої величини
    тіла — тут ні того, ні того, тож бік невідомий. Моделі-стилістці — виміряне: частка кадру
    мотиву (відносно кадру свого фото) і що відомо про особу (обхват зап'ястя, зріст), —
    судить вона. Сила «утримано» — без ваги в доборі (як K-COL-10, K-WCH-01)."""
    if not тіло:
        return []
    о = тіло.get("обхвати") or {}
    зап, з = о.get("зап'ястя"), тіло.get("зріст")
    if not зап and not з:
        return []
    зн = []
    for e in одна_на_річ(E):
        мп = e.get("масштаб_відн")
        if мп is None: continue
        _р = e.get("річ") or e.get("id")
        _заяви_суті = [_ВМ.заява("motif_scale_and_person_not_judged", motif_frame_share=round(float(мп), 3),
                                 **(dict(wrist_cm=round(float(зап), 1)) if зап else {}),
                                 **(dict(height_cm=round(float(з))) if з else {}),
                                 items=[_р], recipient="stylist")]
        зн.append(_зн("K-SIL-06", "утримано", _ВМ.суть_кодом(_заяви_суті, [_р]), [_р],
            "масштаб мотиву ∝ масштабу особи (корпус K-SIL-06) — без коефіцієнта й порогу; частка "
            "кадру мотиву (%.3f) і кістяк особи — різні величини без похибки, тож бік код не називає, "
            "виміряне — моделі" % float(мп),
            заяви=_заяви_суті, учасники=dict(речі=[_р])))
    return зн
