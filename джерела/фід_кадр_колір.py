# ── ВИМІРИ КАДРІВ ГАЛЕРЕЇ (ноутбук, `жнива_кадри.py`) ─────────────────────────
# {"мета": {...}, "записи": {id: [{файл, url, lab, слово, частка, маска, частка_маски}]}}.
# Лежить поруч із модулем, як і збагачення; `.json.gz` їде у вантаж збірки
# (`build_артефакт._покласти_кадри`). Нема файла — порожній словник, і рішення бачить
# лише кадр жнив.
КАДРИ_ІМ = "каталог_кадри.json"
_КАДРИ_КЕШ = {}

# ── ВЖИТОК СЛОВА (CLAUDE.md п.9, рядок 59) ────────────────────────────────────
# Найменше кадрів, на яких крамниці вжили слово, щоб межі вжитку були межами, а не
# випадком: 5-й і 95-й перцентилі з 20 точок відтинають по одній точці з кожного краю.
# На каталог_повний таке вжиток мають 38 слів із 49 однослівних полів кольору.
ВЖИТОК_МІН = 20
ВЖИТОК_КРАЇ = (0.05, 0.95)
# Тон нижче цієї хроми — шум кута, і його не судить ні вжиток, ні `verify.перевірити`
# (той самий поріг C* ≥ 10 стоїть там у перевірці дуги).
ТОН_ВІД_C = 10
# РОЗМИТИЙ ТОН — НЕ МЕЖА. Вжиток слова збирається з УСІХ кадрів, що їх крамниці так
# назвали, отже і з кадрів чужого варіанта — саме тих, які тут шукаються. Де їх багато,
# тон розповзається: «фіолетовий» на 27 кадрах має 95-й перцентиль відхилу 143°, і
# кемеловий светр emmeliedelage ж-04374 (h 58°) лягав би «у вжиток» фіолетового. Тому
# тон вжитку, ширший за найширшу дугу самого лексикону (півдуги «блакитного» — 45°), за
# межу не править: хроматичний кадр такого слова судить вікно лексикону.
ТОН_СТЕЛЯ = max(((в[4][1] - в[4][0]) % 360) / 2.0 for в in V.ЛЕКСИКОН.values() if в[4])

# ── КЛАС ПЛИТКИ (контактний аркуш ноутбука, `жнива_кадри.виміряти_річ`) ─────
# Кадр чужої речі, бирки, упаковки чи підошви — не свідок кольору речі. Першим на
# картку стає лише кадр, де річ ціла (окремо чи на людині); деталь тканини свідчить про
# колір, але картки собою не заступає. Кадр без класу (аркуша не питали) — як доти.
НЕ_СВІДКИ = frozenset(("етикетка", "упаковка", "інша_річ", "порожня", "підошва"))
КАДР_КАРТКИ = frozenset(("ціла_річ", "на_моделі"))

_КОНТЕКСТ = {}


def читати_кадри(тека=None):
    """{id: [вимір кадру]} з `каталог_кадри.json` (або `.json.gz`) поруч із модулем; {} без файла.

    Кешується за (шлях, mtime), як `читати_збагачення`: рішення кличуть і каталог, і
    картка, а файл лежить незмінним увесь сеанс."""
    тека = тека or os.path.dirname(os.path.abspath(__file__)) or "."
    for ш in (os.path.join(тека, КАДРИ_ІМ), os.path.join(тека, КАДРИ_ІМ + ".gz")):
        if not os.path.exists(ш):
            continue
        ключ = (ш, os.path.getmtime(ш))
        if ключ not in _КАДРИ_КЕШ:
            with (gzip.open(ш, "rt", encoding="utf-8") if ш.endswith(".gz")
                  else open(ш, encoding="utf-8")) as f:
                _КАДРИ_КЕШ.clear()
                _КАДРИ_КЕШ[ключ] = (json.load(f).get("записи") or {})
        return _КАДРИ_КЕШ[ключ]
    return {}


def _перцентиль(xs, p):
    """Значення на частці `p` відсортованого ряду (нижній сусід, без інтерполяції)."""
    xs = sorted(xs)
    return xs[int(p * (len(xs) - 1))]


def _відхил(h, центр):
    """Кутова відстань тону `h` від `центр`, 0–180°."""
    return abs((h - центр + 180.0) % 360.0 - 180.0)


def межі_вжитку(точки):
    """Межі вжитку слова з точок (L, C, h): L* і C* між крайніми перцентилями, тон — у
    межах 95-го перцентиля відхилу від кругового середнього (лише точки з C* ≥ `ТОН_ВІД_C`);
    тон, розмитий ширше за `ТОН_СТЕЛЯ` або з замалої кількості точок, — None."""
    н, в = ВЖИТОК_КРАЇ
    тони = [h for L, C, h in точки if C >= ТОН_ВІД_C]
    центр = відхил = None
    if len(тони) >= ВЖИТОК_МІН // 2:
        центр = math.degrees(math.atan2(sum(math.sin(math.radians(h)) for h in тони),
                                        sum(math.cos(math.radians(h)) for h in тони))) % 360.0
        відхил = _перцентиль([_відхил(h, центр) for h in тони], в)
        if відхил > ТОН_СТЕЛЯ:
            центр = None
    return dict(L=(_перцентиль([т[0] for т in точки], н), _перцентиль([т[0] for т in точки], в)),
                C=(_перцентиль([т[1] for т in точки], н), _перцентиль([т[1] for т in точки], в)),
                тон=центр, відхил=відхил, кадрів=len(точки))


def у_межах(межі, lab):
    """Чи вимір `lab` у межах вжитку слова: True / False, або None — коли кадр хроматичний, а
    тону вжиток не має (розмитий чи замало точок) і судити його мусить вікно лексикону."""
    L, C, h = CS.lch(lab)
    if not (межі["L"][0] <= L <= межі["L"][1] and межі["C"][0] <= C <= межі["C"][1]):
        return False
    if C < ТОН_ВІД_C:
        return True
    return None if межі["тон"] is None else _відхил(h, межі["тон"]) <= межі["відхил"]


def узгоджений(вжиток, слово, lab, сім):
    """Чи кадр із виміром `lab` (сім'я тону `сім`) показує колір слова `слово` (ключ лексикону).

    Та сама сім'я — так. Інша — вирішують межі вжитку слова в каталозі, а де вжиток мовчить
    (слова без вжитку, хроматичний кадр при розмитому тоні) — вікно лексикону з сусідами тієї
    ж сім'ї (`verify.перевірити`)."""
    if сім is not None and сім == V.сім_я_слова(слово):
        return True
    межі = вжиток.get(слово)
    в = у_межах(межі, lab) if межі else None
    if в is not None:
        return в
    return V.перевірити(lab, назва=слово)["вердикт"] != "відкинуто"


def _з_варіантом(o, вар):
    """Офер зі словом варіанта в полі кольору (`фід_варіант`); без варіанта — той самий."""
    if not вар:
        return o
    return dict(o, колір_сирий=вар["слово"],
                колір_назва=next(ч for ч in _СЕП_КОЛЬОРУ.split(вар["слово"]) if ч.strip()).strip())


def контекст(offers, збагачення, спільні, сестри=None, ключ=None):
    """Те, що рішенню треба знати про ВЕСЬ каталог: сестри варіантів, вжиток слів, виміри кадрів.

    `спільні` — `фід_фото._спільні_фото(offers)`, `сестри` — `фід_варіант.сестри_варіантів
    (offers)`: викликач їх уже має (без `сестри` — рахуються тут). `ключ` — будь-що хешоване,
    що міняється разом із фідом і збагаченням (шлях, mtime, id словника): тоді картка, що
    читає той самий фід після каталогу, бере готовий контекст, а не рахує вдруге; словник
    збагачення контекст тримає при собі, тож його id не перейде до іншого словника.
    ВЖИТОК — лише з поля кольору, що називає ОДНЕ слово лексикону (після слова варіанта):
    «Чорний, Білий» не каже, котрий із двох на фото."""
    if ключ is not None and ключ in _КОНТЕКСТ:
        return _КОНТЕКСТ[ключ]
    сестри = сестри_варіантів(offers) if сестри is None else сестри
    точки = {}
    for o in offers:
        зб = збагачення.get(o.get("id"))
        if not _збагачення_придатне(зб):
            continue
        мг = o.get("магазин") or str(o.get("id") or "").split("@")[-1]
        if чужий_кадр(зб.get("фото"), спільні.get(мг) or {}):
            continue
        o = _з_варіантом(o, слово_варіанта(o, зб, сестри))
        поле = o.get("колір_сирий") or o.get("колір_назва")
        слова = _слова_кольору_крамниці(поле, поле_кольору=True) if поле else []
        if len(слова) == 1:
            точки.setdefault(слова[0], {})[_файл_фото(зб["фото"])] = CS.lch(колір_збагачення(зб)[1])
    к = dict(сестри=сестри, спільні=спільні, кадри=читати_кадри(), _збагачення=збагачення,
             вжиток={с: межі_вжитку(list(т.values())) for с, т in точки.items() if len(т) >= ВЖИТОК_МІН})
    if ключ is not None:
        _КОНТЕКСТ.clear()
        _КОНТЕКСТ[ключ] = к
    return к


def рішення(o, зб, к):
    """Увесь ланцюг для читача без запису каталогу (картка, прилади): слово варіанта
    (`фід_варіант`) → спір (`колір_спір`) → кроки 1–2 (`після_спору`). Каталог кличе ті
    самі два перші кроки сам, а сюди приходить лише по `після_спору` — тож обидва читачі
    приймають одне рішення. До словника `після_спору` додає `o` і `вар`."""
    вар = слово_варіанта(o, зб, к["сестри"])
    o = _з_варіантом(o, вар)
    р = після_спору(o, зб, колір_спір(зб, o) if зб else None, к)
    р.update(o=o, вар=вар)
    return р


def після_спору(o, зб, спір, к):
    """Кадр, який картка ставить першим, і колір речі, коли кадр жнив і слово крамниці розійшлись.

    `o` — офер уже зі словом варіанта; `зб` — придатне збагачення, кадр якого не чужий (або
    None); `спір` — `колір_спір` для цього `o`; `к` — `контекст`. Повертає dict:
      спір    — позначка `колір_спір`, коли колір лишається за словом крамниці; None — колір з фото;
      позначка — спір, який переважили кадри (крок 2): колір з фото, позначка лишається в записі;
      кадр    — адреса кадру, що стає першим замість кадру жнив (крок 1), або None;
      стан    — None (кадру жнив нема), «свій», «свій_кадр» або «інший_колір»;
      слово, фото — ключі лексикону: колір речі (слово крамниці) і колір на кадрі жнив."""
    р = dict(спір=спір, позначка=None, кадр=None, стан=("свій" if зб else None), слово=None, фото=None)
    if not спір:
        return р
    слово, (фото, lab_фото, _) = спір["крамниця"], колір_збагачення(зб)
    р.update(слово=слово, фото=фото)
    виміри = {_файл_фото(зб.get("фото")): (V.сім_я_слова(фото), lab_фото)}
    не_на_картку = set()
    for в in к["кадри"].get(o.get("id")) or ():
        if (в.get("слово") in V.ЛЕКСИКОН and в.get("файл") and в.get("lab")
                and в.get("клас") not in НЕ_СВІДКИ):
            виміри.setdefault(в["файл"], (V.сім_я_слова(в["слово"]), tuple(в["lab"])))
            if в.get("клас") and в["клас"] not in КАДР_КАРТКИ:
                не_на_картку.add(в["файл"])
    свої = {ф for ф, (сім, lab) in виміри.items() if узгоджений(к["вжиток"], слово, lab, сім)}
    if _файл_фото(зб.get("фото")) in свої:
        return р
    # (2) кадри згодні ПРОТИ слова крамниці — колір з фото за §5, спір лишається позначкою
    проти = collections.Counter(сім for ф, (сім, lab) in виміри.items() if ф not in свої)
    if len(виміри) >= 2 and проти.most_common(1)[0][1] / len(виміри) >= ЗБАГАЧЕННЯ_ЗГОДА:
        р.update(спір=None, позначка=dict(спір, рішення="фото", кадрів=len(виміри),
                                           проти=проти.most_common(1)[0][1]))
        return р
    # (1) кадр кольору речі — першим на картці; нема — стан для заяви
    спільні_мг = к["спільні"].get(o.get("магазин") or str(o.get("id") or "").split("@")[-1]) or {}
    for u in o.get("фото") or ():
        ф = _файл_фото(u)
        if ф in свої and ф not in не_на_картку and not спільна_картинка(ф, спільні_мг):
            р.update(кадр=u, стан="свій_кадр")
            return р
    р["стан"] = "інший_колір"
    return р
