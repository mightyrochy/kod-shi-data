from фід_розбір import _СЕП_КОЛЬОРУ
from фід_збагачення import (колір_спір, колір_збагачення, _збагачення_придатне,
                            _слова_кольору_крамниці, ЗБАГАЧЕННЯ_ЗГОДА)
