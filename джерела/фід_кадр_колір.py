# ── ВИМІРИ КАДРІВ ГАЛЕРЕЇ (ноутбук, `жнива_кадри.py`) ─────────────────────────
# {"мета": {...}, "записи": {id: [{файл, url, lab, слово, частка, маска, частка_маски}]}}.
# Лежить поруч із модулем, як і збагачення; `.json.gz` їде у вантаж збірки
# (`build_артефакт._покласти_кадри`). Нема файла — порожній словник, і рішення бачить
# лише кадр жнив.
КАДРИ_ІМ = "каталог_кадри.json"
КАДРИ_КЕШ = {}

# ── КЛАС ПЛИТКИ (контактний аркуш ноутбука, `жнива_кадри.виміряти_річ`) ─────
# Кадр чужої речі, бирки, упаковки чи підошви — не свідок кольору речі. Першим на
# картку стає лише кадр, де річ ціла (окремо чи на людині); деталь тканини свідчить про
# колір, але картки собою не заступає. Кадр без класу (аркуша не питали) — як доти.
НЕ_СВІДКИ = frozenset(("етикетка", "упаковка", "інша_річ", "порожня", "підошва"))
КАДР_КАРТКИ = frozenset(("ціла_річ", "на_моделі"))

_КОНТЕКСТ = {}


def читати_кадри(тека=None):
    """{id: [вимір кадру]} з `каталог_кадри.json` (або `.json.gz`) поруч із модулем; {} без файла.

    Кешується за (шлях, mtime), як `читати_збагачення`: рішення кличуть і каталог, і
    картка, а файл лежить незмінним увесь сеанс."""
    тека = тека or os.path.dirname(os.path.abspath(__file__)) or "."
    for ш in (os.path.join(тека, КАДРИ_ІМ + ".gz"), os.path.join(тека, КАДРИ_ІМ)):  # .gz першим: `фід_збагачення.читати_збагачення`
        if not os.path.exists(ш):
            continue
        ключ = (ш, os.path.getmtime(ш))
        if ключ not in КАДРИ_КЕШ:
            with (gzip.open(ш, "rt", encoding="utf-8") if ш.endswith(".gz")
                  else open(ш, encoding="utf-8")) as f:
                КАДРИ_КЕШ.clear()
                КАДРИ_КЕШ[ключ] = (json.load(f).get("записи") or {})
        return КАДРИ_КЕШ[ключ]
    return {}


def узгоджений(слово, lab, сім):
    """Чи кадр із виміром `lab` (сім'я тону `сім`) показує колір слова `слово` (ключ лексикону).

    Та сама сім'я — так. Інша — вирішує вікно вжитку слова з сусідами тієї ж сім'ї
    (`verify.перевірити`, `verify.ВЖИТОК`) — те саме, що судить спір кольору."""
    if сім is not None and сім == V.сім_я_слова(слово):
        return True
    return V.перевірити(lab, ім=слово)["вердикт"] == "прийнято"


def _з_варіантом(o, вар):
    """Офер зі словом варіанта в полі кольору (`фід_варіант`); без варіанта — той самий."""
    if not вар:
        return o
    return dict(o, колір_сирий=вар["слово"],
                колір_назва=next(ч for ч in _СЕП_КОЛЬОРУ.split(вар["слово"]) if ч.strip()).strip())


def контекст(offers, збагачення, спільні, сестри=None, ключ=None):
    """`контекст_кроками`, доведений до кінця за один виклик."""
    return _ФР.ганяти(контекст_кроками(offers, збагачення, спільні, сестри, ключ))


def контекст_кроками(offers, збагачення, спільні, сестри=None, ключ=None):
    """Генератор: папки товару (≈ 1,5 с у Pyodide) рахуються шматками (`фід_розбір.ганяти`).

    Те, що рішенню треба знати про ВЕСЬ каталог: сестри варіантів і виміри кадрів.

    `спільні` — `фід_фото.спільні_фото(offers)`, `сестри` — `фід_варіант.сестри_варіантів
    (offers)`: викликач їх уже має (без `сестри` — рахуються тут). `ключ` — будь-що хешоване,
    що міняється разом із фідом і збагаченням (шлях, mtime, id словника): тоді картка, що
    читає той самий фід після каталогу, бере готовий контекст, а не рахує вдруге; словник
    збагачення контекст тримає при собі, тож його id не перейде до іншого словника.
    Вжиток слів — у лексиконі, `verify.ВЖИТОК`."""
    if ключ is not None and ключ in _КОНТЕКСТ:
        return _КОНТЕКСТ[ключ]
    сестри = сестри_варіантів(offers) if сестри is None else сестри
    yield
    кадри = читати_кадри()
    yield
    к = dict(сестри=сестри, спільні=спільні, кадри=кадри, _збагачення=збагачення)
    if ключ is not None:
        # два останні ключі, а не один: каталог і картка, що читають фід різними шляхами,
        # інакше витісняли б контекст одне одного на кожному виклику
        while len(_КОНТЕКСТ) >= 2:
            _КОНТЕКСТ.pop(next(iter(_КОНТЕКСТ)))
        _КОНТЕКСТ[ключ] = к
    return к


def слово_варіанта(o, зб, сестри):
    """dict(слово, поле, джерело, за_чим) — слово крамниці для ЦЬОГО запису, або None.

    `зб` — придатне збагачення запису (кадр не чужий) або None; `сестри` —
    `сестри_варіантів` усього каталогу. None — поле кольору лишається як є.
    Спершу слово варіанта моделі (кроки 1–3), потім слово назви з кадром (крок 4)."""
    return слово_моделі(o, сестри) or слово_назви_з_кадром(o, зб)


# Слова назви для `V.слово_крамниці`: дефіс лишається в слові («світло-коричневий» — слово
# крамниці з модифікатором), а для переліку кольорів назви дефіс — межа («чорно-білі»).
_МЕЖА_СЛОВА = re.compile(r"[^\w'’-]+")


_МЕЖА_КОЛЬОРУ = re.compile(r"[^\w'’]+")


def _у_світлоті(lab, ім):
    """Світлота `lab` у межах вікна вжитку САМОГО слова `ім` (`V.вікно_вжитку`), без сусідів сім'ї."""
    Lmin, Lmax = V.вікно_вжитку(ім)[:2]
    return Lmin <= V.lch(lab)[0] <= Lmax


def слово_назви_з_кадром(o, зб):
    """Крок 4: dict як у `слово_варіанта` — слово кольору НАЗВИ, коли поле кольору
    суперечить і їй, і виміру кадру жнив, а назва з кадром згодні (п.18); інакше None.

    Діє лише там, де без нього колір лишився б за полем: вимір у спорі з полем (`колір_спір`),
    який не переважили кадри галереї (крок 2 `фід_кадр_колір.після_спору`), або у вікні вжитку
    слова поля (`фід_збагачення.назва_кольору` тоді лишає слово поля).
      · поле суперечить кадру — сім'я тону виміру (те, що вимір каже сам) не сім'я жодного
        слова поля;
      · назва з кадром згодні — вимір у вікні вжитку слова назви (`V.перевірити`), і його
        світлота — у вікні самого слова: `перевірити` приймає й вікна сусідів сім'ї, а
        «капучино» — ключ «графіт» (L* 2–56), і світла сумка, виміряна «срібним» (L* 72), —
        не графіт (ж-08158); коли назва називає кілька кольорів — ще й у сім'ї слова назви;
      · річ на кадрі двоколірна (`колір_другий`) — поле лишається (п.18: двоколірні лишають
        вікно слова): ж-09572 — замша «капучино», а головним виміряно темну підошву;
      · назва, що називає й колір поля («СВІТЛА ОЛИВА + АЙВОРІ» при полі «Світла оливка»,
        «чорно-білі» при «білий»), — не свідок проти поля;
      · близьке слово — центр вікна слова поля у вікні вжитку слова назви («білий» при
        «молочний»): поле вже каже колір назви.
    Слово назви — ключ `V.назва_кольору`; у запис іде те слово назви, яке написала крамниця
    («світло-коричневий», «капучино»), коли `V.слово_крамниці` читає його тим самим ключем, —
    інакше сам ключ."""
    # назва фіду, що не пройшла суд назви (`назва_речі`: речення опису, розділ, бренд — тоді
    # картка показує іншу назву), — не свідок кольору речі: «…оброблена бейкою чорного
    # кольору…» (ж-00432@morandi, сіро-синій сарафан), «…поєднується з молочними…» (ж-01778)
    if o.get("назва_показу_джерело") not in (None, "фід"):
        return None
    поле = o.get("колір_сирий") or o.get("колір_назва") or ""
    слова = [с["ім"] for с in map(V.слово_крамниці, _СЕП_КОЛЬОРУ.split(поле)) if с]
    назва = o.get("назва") or ""
    ім = V.назва_кольору(назва)
    if not (зб and слова and ім):
        return None
    у_назві = {ім} | {с["ім"] for с in map(V.слово_крамниці, _МЕЖА_КОЛЬОРУ.split(назва)) if с}
    фото, lab, _ = колір_збагачення(зб)
    сім = V.сім_я_слова(фото)
    сім_поля = {V.сім_я_слова(с) for с in слова}
    прийнято = lambda lab_, с: V.перевірити(lab_, ім=с)["вердикт"] == "прийнято"
    if (lab is None or сім is None or зб.get("колір_другий") or у_назві & set(слова) or сім in сім_поля
            or not (прийнято(lab, ім) and _у_світлоті(lab, ім))
            or (len(у_назві) > 1 and сім != V.сім_я_слова(ім))
            or any(прийнято(_центр_вікна(V.ЛЕКСИКОН[с]), ім) for с in слова if с in V.ЛЕКСИКОН)):
        return None
    спір = колір_спір(зб, o)
    if not (спір or any(прийнято(lab, с) for с in слова)):
        return None
    if спір:
        # кадри галереї згодні проти поля (крок 2 `після_спору`) — колір і так з фото
        # (ж-09677: три кадри «графіт» проти «бежевий»). Контекст — лише виміри кадрів.
        if після_спору(o, зб, спір, dict(кадри=читати_кадри(), спільні={}))["позначка"]:
            return None
    слово = next((с["назва"] for с in map(V.слово_крамниці, _МЕЖА_СЛОВА.split(назва))
                  if с and с["ім"] == ім), ім)
    return dict(слово=слово, поле=поле, джерело="слово назви з кадром",
                за_чим="поле «%s» суперечить і назві, і кадру («%s»); слово назви «%s»" % (поле, фото, слово))


def рішення(o, зб, к):
    """Увесь ланцюг для читача без запису каталогу (картка, прилади): слово варіанта
    (`фід_варіант`) → спір (`колір_спір`) → кроки 1–2 (`після_спору`). Каталог кличе ті
    самі два перші кроки сам, а сюди приходить лише по `після_спору` — тож обидва читачі
    приймають одне рішення. До словника `після_спору` додає `o` і `вар`."""
    вар = слово_варіанта(o, зб, к["сестри"])
    o = _з_варіантом(o, вар)
    р = після_спору(o, зб, колір_спір(зб, o) if зб else None, к)
    р.update(o=o, вар=вар)
    return р


def після_спору(o, зб, спір, к):
    """Стан кадру жнив і колір речі, коли кадр жнив і слово крамниці розійшлись.

    `o` — офер уже зі словом варіанта; `зб` — придатне збагачення, кадр якого не чужий (або
    None); `спір` — `колір_спір` для цього `o`; `к` — `контекст`. Повертає dict:
      спір    — позначка `колір_спір`, коли колір лишається за словом крамниці; None — колір з фото;
      позначка — спір, який переважили кадри (крок 2): колір з фото, позначка лишається в записі;
      кадр    — завжди None: кадру на заміну кадру жнив картка не шукає (наряд 5.2);
      стан    — None (кадру жнив нема), «свій» або «інший_колір»;
      слово, фото — ключі лексикону: колір речі (слово крамниці) і колір на кадрі жнив."""
    р = dict(спір=спір, позначка=None, кадр=None, стан=("свій" if зб else None), слово=None, фото=None)
    if not спір:
        return р
    слово, (фото, lab_фото, _) = спір["крамниця"], колір_збагачення(зб)
    р.update(слово=слово, фото=фото, вікно_кадру=_вікно_свідка(фото, lab_фото, _))
    виміри = ({_файл_фото(зб.get("фото")): (V.сім_я_слова(фото), lab_фото)}
              if lab_фото is not None else {})
    for в in к["кадри"].get(o.get("id")) or ():
        if (в.get("слово") in V.ЛЕКСИКОН and в.get("файл") and _КР_ТИП.точка_кольору(в)
                and в.get("клас") not in НЕ_СВІДКИ):
            виміри.setdefault(в["файл"], (V.сім_я_слова(в["слово"]), tuple(_КР_ТИП.точка_кольору(в))))
    свої = {ф for ф, (сім, lab) in виміри.items() if узгоджений(слово, lab, сім)}
    if _файл_фото(зб.get("фото")) in свої:
        return р
    # (2) кадри згодні ПРОТИ слова крамниці — колір з фото за §5, спір лишається позначкою
    проти = collections.Counter(сім for ф, (сім, lab) in виміри.items() if ф not in свої)
    if len(виміри) >= 2 and проти and проти.most_common(1)[0][1] / len(виміри) >= ЗБАГАЧЕННЯ_ЗГОДА:
        р.update(спір=None, позначка=dict(спір, рішення="фото", кадрів=len(виміри),
                                           проти=проти.most_common(1)[0][1]))
        return р
    # (1) кадр жнив не в кольорі слова — стан для заяви й вікна. Кадру на заміну
    # картка не шукає: кадр галереї, чий вимір тієї ж сім'ї тону, що слово
    # крамниці, — здогадка про варіант, не доказ власності (п.12); на 59 картках «свій_кадр»
    # така заміна ставила першим креслення (ж-02894) і чотири пари взуття (ж-09933).
    р["стан"] = "інший_колір"
    return р


# ── КОЛІР РЕЧІ, ЧИЙ КАДР КАРТКИ ІНШОГО КОЛЬОРУ ──
# Колір такої речі — вікно, що накриває обох свідків: слово крамниці (п.9: воно лишається
# словом речі) і кадр, який бачить жінка. Яким із двох річ є, код не знає, і вікно це
# каже числами: правила, що судять вікном (`колір_річ.межі_кольору`), там, де свідки
# розходяться, кажуть «без входу», а модель дістає світлоту обох і колір кадру другим
# свідком (`дріт_моделі.річ`).
def _вікно_свідка(слово, lab, за_чим):
    """(L0, L1, C0, C1, дуга) кадру: точка, коли колір кадру виміряно (hex узгоджений зі
    словом, `колір_збагачення`), інакше вікно лексикону його слова; None — нема чого."""
    if lab is not None:
        L, C, h = _КС.lch(tuple(lab))
        return (L, L, C, C, None if C < V.ДРІЖ_AB else (h, h))
    return V.ЛЕКСИКОН.get(слово)


def вікно_з_кадром(вікно, вікно_кадру):
    """Вікно (L0, L1, C0, C1, дуга), що накриває вікно слова крамниці `вікно` і колір кадру
    `вікно_кадру` (`_вікно_свідка`); дуга — найкоротша, що тримає обидві, None — коли
    котрийсь свідок тону не має (ахромат слова крамниці). Без кадру — `вікно` як є."""
    if not вікно or not вікно_кадру:
        return вікно
    а, б = вікно, вікно_кадру
    if а[4] is None:
        дуга = None
    elif б[4] is None:
        дуга = а[4]                                   # кадр без тону — дуга слова лишається
    else:
        зайняті = set()
        for lo, hi in (а[4], б[4]):
            lo, hi = int(float(lo)) % 360, int(round(float(hi))) % 360
            зайняті.update((lo + k) % 360 for k in range(((hi - lo) % 360) + 1))
        # найдовша дірка кола — поза дугою; решта кола — дуга, що тримає обох
        вільні = sorted(set(range(360)) - зайняті)
        if not вільні:
            дуга = (0.0, 359.0)
        else:
            дірки, поч = [], вільні[0]
            for x, y in zip(вільні, вільні[1:] + [None]):
                if y != x + 1:
                    дірки.append((поч, x)); поч = y
            if len(дірки) > 1 and дірки[0][0] == 0 and дірки[-1][1] == 359:
                дірки = [(дірки[-1][0], дірки[0][1] + 360)] + дірки[1:-1]
            п, к = max(дірки, key=lambda д: д[1] - д[0])
            дуга = (float((к + 1) % 360), float((п - 1) % 360))
    return (min(float(а[0]), float(б[0])), max(float(а[1]), float(б[1])),
            min(float(а[2]), float(б[2])), max(float(а[3]), float(б[3])), дуга)


def клас_кадру(ід, url, к):
    """Клас плитки кадру `url` цієї речі з вимірів галереї, або None (кадру не міряли).

    Класи — ті самі, що дає контактний аркуш ноутбука (`жнива_кадри.виміряти_річ`):
    ціла_річ, на_моделі, деталь, підошва, етикетка, упаковка, інша_річ, порожня.
    ЧОМУ ЦЕ ЧИТАЄ КАРТКА, А НЕ ЛИШЕ РІШЕННЯ ПРО КОЛІР (П11 звіту Research, наряд С-1):
    тип фото — змінна відгуку жінки: «не моє» на речі, знятій деталлю тканини, і «не
    моє» на речі, знятій на моделі, — різні свідчення, і доти вердикт не казав, яке з
    них записано. Тут лише ЗАПИС: на добір клас кадру не діє, доки вимір не покаже, що
    він розводить вердикти.
    Файл кадру звіряється тим самим `_файл_фото`, що й у `після_спору`: виміри лежать
    уже в цій формі, а на картку йде повна адреса."""
    ф = _файл_фото(url)
    if not (ф and ід):
        return None
    for в in к["кадри"].get(ід) or ():
        if в.get("файл") == ф:
            return в.get("клас") or None
    return None
