"""фід_кадр_колір.py — ЯКИЙ кадр стоїть на картці першим за кольором і ЯКИЙ колір у речі,
коли кадр і слово крамниці розходяться.

Розбіжність між словом крамниці й виміром кадру ділиться на два роди:
  · КАДР ІНШОГО ВАРІАНТА — крамниця ставить одну галерею на всі кольори моделі, і першим
    стоїть чужий колір: wearme ж-05473 («чорний» — на картці бежева куртка, чорна — 5-й
    кадр), maxa ж-00898 («білий» — рожеві штани), bella-bicchi ж-08474 («сірий» — біле
    пальто);
  · МЕЖА СЛОВА — на кадрі та сама річ і той самий колір, але вимір лягає у вікно
    сусідньої сім'ї лексикону: «шоколадний» светр вимірявся «чорним», «темно-синя»
    спідниця — «чорною», «блакитні» джинси — «білими». Крамниця тут права, а
    фото показує саме те, що вона назвала.

Свідок «кадр показує колір речі» судиться ВЖИТКОМ слова (аудит/ПРОДУКТ.md п.9: «якщо
модель і магазини називають його бежевим, значить він бежевий»): вимір кадру приймається
за колір слова, коли він у тій самій сім'ї тону АБО лежить у вікні вжитку слова
(`verify.перевірити`: вікно вжитку слова, `verify.ВЖИТОК`, або вікно лексикону сусіда
тієї ж сім'ї). Вжиток живе в лексиконі: ті самі вікна судять вимір, спір кольору
(`фід_збагачення.колір_спір`) і цей кадр, і дають спектр плашці основ. Код порівнює лише
числа й коди: ключ лексикону, сім'ю, L*/C*/h, файл кадру.

Рішення одне на двох читачів — запис каталогу (`фід_каталог`) і картку
(`міст_опис._фото_речі`), — і складається з двох кроків, лише для записів у спорі:
  (1) КАДР ІНШОГО КОЛЬОРУ. Кадр жнив показує колір речі — нічого не міняється. Ні — запис
      несе `кадр_кольору` зі станом «інший_колір», і суд кладе заяву кодом
      (`суд_річ.кадр_іншого_кольору`, слова — мовна модель, п.12). Кадру на заміну картка не
      шукає: кадр галереї, виміряний у сім'ї слова крамниці, — здогадка про варіант
      сім'єю тону, не доказ власності (п.12); чий кадр, вирішує `фід_власник_кадру`
      (байти, не слова).
  (2) КОЛІР РЕЧІ. Коли виміряних кадрів хоча б два і не менше `ЗБАГАЧЕННЯ_ЗГОДА` (0.9) з
      них — одна сім'я поза кольором слова крамниці, свідки згодні ПРОТИ поля: колір з фото
      за правилом §5, а спір лишається в записі позначкою (`рішення` «фото»). Інакше — слово
      крамниці й позначка.
  Правило §5 не міняється: колір з фото поза вікном слова крамниці й далі береться лише за
  згоди свідків ≥ 0.9 (вимір у вікні — з `ЗГОДА_ВІКНОМ`, Р1а, `фід_збагачення`), а свідками
  можуть бути кілька кадрів, а не один.

ЧОГО ТУТ НЕМА І ЧОМУ. Вимір кожного кадру галереї — робота моделі зору (маска ATR → SAM,
k-means у Lab — `жнива_колір.виміряти_фото`), і в хмарі її нема. Тому кадри, крім кадру
жнив, приходять із файла `каталог_кадри.json.gz`, який пише ноутбук (`жнива_кадри.py`);
без файла кроки (1) і (2) бачать один кадр — кадр жнив, — і діє лише заява. Свідок «група
варіантів за id» не доданий: груп ≥ 2 з однаковим полем кольору й різними вимірами в
каталозі 11, у 10 поле кольору порожнє або «принт» (колір з фото там і так береться), а
в єдиній kasandra (група з назви товару) «різні виміри» — темно-коричневий, виміряний
чорним, тобто межа слова, і свідок перевернув би колір хибно.
"""
