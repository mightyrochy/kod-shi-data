# ── ЗБАГАЧЕННЯ З ФОТО (17.09.2026, `жнива_збагачення.py`) ────────────────────
# ЩО ЦЕ ЛІКУЄ. Живий шлях (стенд, показ) іде з `ліміт_фото=0`, тобто колір речі
# брався зі СЛОВА крамниці — вікно назви, впевненість 0.35; крій був відомий у
# чверті речей, а слово матеріалу до пулу не доходило. Дуга схеми і правила
# силуету судили здогад. Фото ж є у 100 % речей, і локальна vision-модель описує
# його ОДИН РАЗ, офлайн: `каталог_збагачення.json` за кваліфікованим id.
# Словники опису — ті самі, що читають правила (ЛЕКСИКОН, silhouette.КРОЇ,
# ВОЛОКНА, КЛАСИ_МОТИВУ, рівні довжини, блиск 0–3, формальність 1–10), тому
# поле кладеться як є, без перекладача.
# ЩО ЛИШАЄТЬСЯ ЗАПАСНИМ. Нема файла або речі в ньому, або модель сказала
# «речі не видно» (впевненість 0: логотип, таблиця розмірів) — усе йде старим
# шляхом, слово крамниці працює як доти.
# ЧОГО ФОТО НЕ ПЕРЕКРИВАЄ. СКЛАД із бирки (`матеріал`, «60% віскоза…») — факт
# крамниці, фото волокна не бачить; опис моделі йде лише туди, де крамниця
# слова не дала (`волокно` порожнє). Hex моделі звіряється з її ж словом: 8B
# модель пише «рожевий» і #d4a017 (золото) — див. `колір_збагачення`.
ЗБАГАЧЕННЯ_ІМ = "каталог_збагачення.json"
_ЗБАГАЧЕННЯ_КЕШ = {}
# ПОРІГ УПЕВНЕНОСТІ, НИЖЧЕ ЯКОГО ФОТО НЕ ПЕРЕКРИВАЄ СЛОВО КРАМНИЦІ. Доти тут
# стояло «> 0», тобто опис брався за будь-якої ненульової впевненості, і поріг
# існував лише проти самовизнаного «речі не видно» (рівно 0). Слово крамниці —
# запасний шлях, і межа, за якою він повертається, мусить бути числом у коді, а
# не збігом даних: на цих жнивах записів між 0 і 0.5 немає жодного (вимір
# 17.09.2026: 0.5 — 3, 0.7 — 3, 0.8 — 3, 0.9 — 404, 1.0 — 9 084), тож правило
# нічого не міняє СЬОГОДНІ й тримає межу на наступних жнивах іншою моделлю.
ЗБАГАЧЕННЯ_ПОРІГ = 0.5

# ── КОЛІР З ФОТО — ЛИШЕ ЗА ЗГОДИ СВІДКІВ (18.09.2026, ПЕРЕДАЧА §5) ─────────
# Правило власника про під'єднання збагачення до фіду: колір з фото лише при
# узгодженості ≥ 0.9 або коли крамниця кольору не назвала; спір — лишається
# слово крамниці і позначка. Доти опис з фото перекривав слово крамниці за
# будь-якої «впевненості» ≥ 0.5, а у жнивах v1 впевненість — самооцінка моделі
# (1.0 і на логотипі, і на сукні, описаній замість каблучки ж-07624), тобто
# свідком вона бути не може. ВИМІРЯНО на каталог_повний із жнивами v1: придатних
# 9 478 — згода за сім'єю тону 5 329, крамниця без кольору 1 408, спір 2 741
# (29 %): для них колір повертається до слова крамниці, запис несе `колір_спір`.
ЗБАГАЧЕННЯ_ЗГОДА = 0.9


def _слова_кольору_крамниці(текст):
    """Слова ЛЕКСИКОНУ у слові крамниці, в порядку появи («Білий, Чорний» → обидва)."""
    вих = []
    for частина in _СЕП_КОЛЬОРУ.split(текст or ""):
        с = V.назва_кольору(частина)
        if с and с not in вих:
            вих.append(с)
    return вих


def узгодженість_збагачення(зб, o):
    """(узгодженість 0–1, слова крамниці): чи підтверджує колір з фото інший свідок.

    v2 (`версія` ≥ 2, `жнива_v2`): `впевненість` записана ЗІ ЗГОДИ свідків (маска,
    слово моделі, слово крамниці, друге фото) — береться як є.
    v1: `впевненість` — самооцінка, і єдиний інший свідок — слово крамниці: та сама
    сім'я тону (`V.сім_я_слова`) → 1.0, інша → 0.0. Свідок той самий, що й у гілці
    «назва-вікно» (`param` кольору, інакше назва), щоб обидві гілки читали одне слово.
    """
    кр = _слова_кольору_крамниці(o.get("колір_назва") or o.get("назва") or "")
    if (зб.get("версія") or 1) >= 2:
        return float(зб.get("впевненість") or 0.0), кр
    if not кр:
        return 1.0, кр
    сім = {V.сім_я_слова(с) for с in кр}
    return (1.0 if V.сім_я_слова(зб["колір_основний"]["слово"]) in сім else 0.0), кр


def колір_спір(зб, o):
    """None — колір з фото можна брати; інакше позначка спору для запису."""
    у, кр = узгодженість_збагачення(зб, o)
    if not кр or у >= ЗБАГАЧЕННЯ_ЗГОДА:
        return None
    return dict(модель=зб["колір_основний"]["слово"], крамниця=кр[0], узгодженість=round(у, 2),
                чому=("сім'я тону слова з фото не збіглася зі словом крамниці"
                      if (зб.get("версія") or 1) < 2 else "згода свідків нижча за поріг"))

