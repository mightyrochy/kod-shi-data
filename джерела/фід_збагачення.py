ЗБАГАЧЕННЯ_ЗГОДА = 0.9

# ── СПІР — ЦЕ СІМ'Я, А НЕ ЧИСЛО ЖНИВ; СВІДОК — УСЕ ПОЛЕ КОЛЬОРУ (22.09.2026, рядок 135) ──
# ЩО ТУТ БУЛО. Для жнив v2 `узгодженість_збагачення` брала `впевненість` жниварки як
# є, а свідком крамниці читала лише ПЕРШУ частину поля кольору (`колір_назва`) і лише
# українським лексиконом. Дві дірки, обидві виміряні на каталог_повний (main 6374076,
# 12 198 записів, 3 296 слів крамниці замінено словом із фото):
#   · іншомовне слово поля кольору («brown», «milk», «black») свідком не було, тож
#     «brown → чорний» 21 раз ішло без спору — правило §5 не діяло там, де крамниця
#     слово дала;
#   · жниварка звіряла слово з фото з УСІМ полем («Чорний, Білий»), а фід — з першим
#     словом: з 122 «різних сімей» з українським першим словом у всіх 122 слово з
#     фото — інше слово того ж поля («Чорний, Білий» → «білий»): свідок згоден.
# ЩО СТАЛО. Свідок — усі кольорові частини поля кольору (`V.слово_крамниці`: іншомовні
# теж, як інша поверхня тих самих вікон). Збіг сім'ї з будь-яким словом поля — згода
# (далі поріг v2, як доти). Сім'я слова з фото, якої нема серед слів ПОВНІСТЮ
# прочитаного поля, — СПІР за будь-якої `впевненості` (§5: колір із фото лише за
# згоди зі словом крамниці). Поле зі словом поза лексиконом («Бургунді, Чорний») і
# назва товару без поля судяться як доти (перше слово поля або назва): сім'ї
# невідомого слова код не знає. Слово з фото, яке порівнюється, — те, що ляже в
# запис (`колір_збагачення`, гілка «hex+опис» включно), а не сире слово моделі.
# ВИМІРЯНО ПІСЛЯ на тому самому каталозі: спорів 4 834 → 5 034 (нових 229: іншої
# сім'ї на іншомовному слові 95, тієї ж сім'ї на іншомовному слові з впевненістю v2
# < 0.9 — 129, поле з невідомим першим словом 5; знято 29 — фото збіглося з іншим
# словом поля). Вимір (lab) змінився в 258 записах — рівно в тих, де змінився спір.


def _слова_кольору_крамниці(текст, поле_кольору=False):
    """Слова ЛЕКСИКОНУ у слові крамниці, в порядку появи («Білий, Чорний» → обидва).

    `поле_кольору` — текст з поля кольору крамниці: там кожна частина читається
    `V.слово_крамниці` (іншомовна теж). Назва товару читається лише
    `V.назва_кольору`: латиниця в ній — бренд частіше, ніж колір."""
    вих = []
    for частина in _СЕП_КОЛЬОРУ.split(текст or ""):
        с = ((V.слово_крамниці(частина) or {}).get("ім") if поле_кольору
             else V.назва_кольору(частина))
        if с and с not in вих:
            вих.append(с)
    return вих


def _свідок_крамниці(o):
    """(текст, це_поле_кольору): усе поле кольору крамниці, а без нього — назва товару."""
    поле = o.get("колір_сирий") or o.get("колір_назва")
    return (поле, True) if поле else (o.get("назва") or "", False)


def _поле_прочитане_все(o):
    """Чи поле кольору крамниці є і кожна його частина — слово лексикону (іншомовне теж).

    «Бургунді, Чорний»: «бургунді» лексикон не знає, тож фото «бордовий» проти
    «чорний» НЕ доводить незгоди — невідоме слово й може бути тим кольором, який
    бачить фото. Без поля кольору (свідок — назва товару) — теж False: назва не є
    переліком кольорів речі («з білим коміром»)."""
    текст, поле = _свідок_крамниці(o)
    return bool(поле) and all(V.слово_крамниці(ч) for ч in _СЕП_КОЛЬОРУ.split(текст) if ч.strip())


def узгодженість_збагачення(зб, o):
    """(узгодженість 0–1, слова крамниці): чи підтверджує колір з фото інший свідок.

    v2 (`версія` ≥ 2, `жнива_v2`): `впевненість` записана ЗІ ЗГОДИ свідків (маска,
    слово моделі, слово крамниці, друге фото) — береться як є; сім'ю окремо судить
    `колір_спір`.
    v1: `впевненість` — самооцінка, і єдиний інший свідок — слово крамниці: та сама
    сім'я тону (`V.сім_я_слова`) → 1.0, інша → 0.0. Свідок той самий, що й у гілці
    «назва-вікно» (поле кольору, інакше назва), щоб обидві гілки читали одне слово.
    """
    кр = _слова_кольору_крамниці(*_свідок_крамниці(o))
    if (зб.get("версія") or 1) >= 2:
        return float(зб.get("впевненість") or 0.0), кр
    if not кр:
        return 1.0, кр
    сім = {V.сім_я_слова(с) for с in кр}
    return (1.0 if V.сім_я_слова(колір_збагачення(зб)[0]) in сім else 0.0), кр


def колір_спір(зб, o):
    """None — колір з фото можна брати; інакше позначка спору для запису.

    Спір — коли сім'ї слова з фото нема серед сімей слів поля кольору, прочитаного
    ЦІЛКОМ (за будь-якої `впевненості`), або коли сім'я та сама, а згода свідків v2
    нижча за поріг. Поле з невідомим лексикону словом («Бургунді, Чорний») і назва
    товару без поля судяться як доти: свідок — перше слово поля (або назва), v1 за
    сім'єю, v2 за порогом згоди, — бо сім'ї невідомого слова код не знає."""
    у, кр = узгодженість_збагачення(зб, o)
    if not кр:
        return None
    слово = колір_збагачення(зб)[0]
    _чому_сім = "сім'я тону слова з фото не збіглася зі словом крамниці"
    if V.сім_я_слова(слово) in {V.сім_я_слова(с) for с in кр}:
        if у >= ЗБАГАЧЕННЯ_ЗГОДА:
            return None
        чому = "згода свідків нижча за поріг"
    elif _поле_прочитане_все(o):
        чому = _чому_сім
    else:
        кр = _слова_кольору_крамниці(o.get("колір_назва") or o.get("назва") or "")
        if not кр:
            return None
        v2 = (зб.get("версія") or 1) >= 2
        if v2 and у >= ЗБАГАЧЕННЯ_ЗГОДА:
            return None
        у, чому = (у, "згода свідків нижча за поріг") if v2 else (0.0, _чому_сім)
    return dict(модель=слово, крамниця=кр[0], узгодженість=round(у, 2), чому=чому)

