# ЩО ТУТ БУЛО. `_накласти_колір` клав у `колір_назва` СЛОВО моделі, тобто з фото
# бралось не лише вимір (lab, hex, площі), а й назва. Слово моделі — одне з 51 слова
# лексикону, а крамниця пише детальніше: brenda «бузково-молочний» і «нюдово білий»
# ставали «білий» (слово власниці 22.09: «але назва магазину більш детальна»).
# ВИМІРЯНО на каталог_повний (main 6374076): зі збагаченням 11 399 записів, зі словом
# крамниці поверх фото 5 772, і в 3 296 назва крамниці замінена іншим словом:
# «молочний → білий» 321, «молоко → білий» 84, «айворі → білий» 35.
# ЩО СТАЛО. Назва — слово крамниці, коли воно колір (його жінка бачить на сторінці
# крамниці). Слово з фото стає назвою, лише коли воно ТОНШИЙ відтінок: його вікно
# лексикону строго всередині вікна слова крамниці (`V.вікно_всередині`), — або коли
# крамниця кольору в полі кольору не дала / дала не колір. Нового «оцінювача
# детальності» нема: критерій — вкладеність вікон. Іншомовне слово крамниці («milk»)
# у назву йде українським словом лексикону («молочний»), як і «черный» → «чорний».
# ВИМІР НЕ ЧІПАЄТЬСЯ: lab, hex, частка і `colors` — з фото, як і доти; обидва слова
# лишаються в записі (`колір_назва_крамниці`, `колір_назва_фото`) з провенансом
# (`колір_назва_джерело`, `колір_назва_за_чим`).
# ВИМІРЯНО ПІСЛЯ (той самий каталог): із 3 296 назва крамниці лишилась у 2 239, спором
# стали 229, слово крамниці не колір — 828 (назва з фото, законно), тонший відтінок
# із фото — 0: жодне вікно лексикону не лежить строго в іншому, і з «темно-/світло-»
# теж (перевірено всі пари): «темно-синій» ширший за «синій» донизу по L* (10 < 15)
# і C* (8 < 12), «графіт» за «сірий» по L* (20 < 25), «шоколадний» за «коричневий»
# по L* і C*, «пудровий» за «рожевий» по C* (5 < 8). Правило стоїть і спрацює, щойно
# якесь вікно звузиться.
def _назва_кольору(слово_фото, крамниця):
    """(назва, джерело, за_чим): яке слово стає `колір_назва` речі з кольором із фото.

    `крамниця` — поле кольору крамниці як є (усі частини); серед них береться перша
    ТІЄЇ Ж сім'ї тону, що й слово з фото. Джерело — «крамниця» або «фото»."""
    частини = [ч.strip() for ч in _СЕП_КОЛЬОРУ.split(крамниця or "") if ч.strip()]
    if not частини:
        return слово_фото, "фото", "крамниця слова кольору в полі кольору не дала"
    прочитані = [(ч, V.слово_крамниці(ч)) for ч in частини]
    кольори = [(ч, с) for ч, с in прочитані if с]
    if not кольори:
        return слово_фото, "фото", "слово крамниці «%s» — не колір лексикону" % частини[0]
    сім = V.сім_я_слова(слово_фото)
    ч, с = next(((ч, с) for ч, с in кольори if V.сім_я_слова(с["ім"]) == сім), (None, None))
    if с is None:
        # спору нема, а слова тієї ж сім'ї в полі нема: або поле має слово поза
        # лексиконом (`_поле_прочитане_все`), або спору не питали — назва з фото,
        # і причина названа тут же
        невідомі = [ч_ for ч_, с_ in прочитані if not с_]
        return слово_фото, "фото", ("слово крамниці «%s» лексикон не знає, а «%s» — іншої сім'ї тону"
                                    % (невідомі[0], кольори[0][0]) if невідомі
                                    else "слово крамниці «%s» іншої сім'ї тону" % кольори[0][0])
    вікно_фото = V.ЛЕКСИКОН[слово_фото]
    як_назва = "«%s»" % ч + ("" if с["як_є"] else " → «%s»%s" % (с["назва"], " (іншомовне)"
                                                                if с["латинка"] else ""))
    if (слово_фото != с["ім"] and tuple(вікно_фото) != tuple(с["вікно"])
            and V.вікно_всередині(вікно_фото, с["вікно"])):
        return слово_фото, "фото", ("тонший відтінок: вікно «%s» лежить усередині вікна слова крамниці %s"
                                    % (слово_фото, як_назва))
    return с["назва"], "крамниця", ("слово крамниці %s; з фото «%s» — %s"
                                    % (як_назва, слово_фото,
                                       "те саме слово лексикону" if слово_фото == с["ім"]
                                       else "та сама сім'я, вікно не всередині вікна слова крамниці"))


def _накласти_колір(r, зб, крамниця=None):
    """Колір з фото — у запис: точка, другий колір і дві площі; назва — `_назва_кольору`.

    `крамниця` — поле кольору крамниці цілком; без нього — `колір_назва` запису."""
    к = зб["колір_основний"]
    слово, lab_осн, за_чим = колір_збагачення(зб)
    r["колір_назва_крамниці"] = r.get("колір_назва")
    r["колір_назва_фото"] = слово
    r["колір_назва"], r["колір_назва_джерело"], r["колір_назва_за_чим"] = _назва_кольору(
        слово, r.get("колір_назва") if крамниця is None else крамниця)
    r["колір_за_чим"] = "фото: %s" % за_чим
    r["колір_hex_фото"] = к.get("hex")
    r["колір_частка"] = к.get("частка")
    # ── КОЛІР З ФОТО — НЕ ЗАВЖДИ ВИМІР (23.09.2026, рядок 141) ──────────────
    # Вимір — лише hex жнив v2 (маска речі, k-means у Lab), узгоджений зі словом.
    # Гілка «слово (hex …)» кладе в точку ЦЕНТР ВІКНА слова моделі, а hex жнив v1
    # — назва кольору, а не вимір («сірий #808080» і на графіті, і на сріблі;
    # вимір на каталог_повний: 391 такий запис, серед hex — #ffffff 39 разів,
    # #f5f5dc — сам CSS «beige»). Обидва несуть поле `колір_не_вимір`, і правило,
    # що порівнює колір двох речей, їх як вимір не судить (`колір_річ.не_вимір`).
    _v1 = (зб.get("версія") or 1) < 2
    if за_чим.startswith("слово"):
        r["колір_не_вимір"] = не_вимір_кольору(
            V.ЛЕКСИКОН[слово], слово, "слово моделі",
            " з опису фото (%s)" % за_чим[len("слово "):].strip("()"))
    elif _v1:
        r["колір_не_вимір"] = не_вимір_кольору(
            V.ЛЕКСИКОН[слово], слово, "hex моделі",
            " (%s, жнива v1: назва кольору, а не вимір пікселів)" % к.get("hex"))
    else:
        r.pop("колір_не_вимір", None)
    д = другий_колір(зб.get("колір_другий"))
    r["колір_другий"] = dict(слово=д[0], lab=д[1], частка=д[2]) if д else None
    if д:
        # ── ДВА КОЛЬОРИ — ДВІ ПЛОЩІ (K-COL-01/02/05/06, K-PAL-10) ────────────
        # `outfit.елементи` ділить площу речі за списком `colors`; без нього річ
        # заходила ОДНИМ кольором на всю свою площу, і біла сорочка в чорну
        # смужку важила в бюджеті хроми стільки ж, скільки суцільно чорна.
        # Це той самий контракт, яким користується піксельний шлях
        # (`areas.образ_з_геометрії`: `colors=[{lab, coverage}]`), тому формат
        # дослівно його — і lab, а не hex: `колір_образу` читає `["lab"]` прямо.
        # ЧАСТКИ НОРМУЮТЬСЯ ДО ОДИНИЦІ. Модель дає частку площі РЕЧІ, і сума по
        # двох названих кольорах менша за неї (решта — дрібні плями, яких модель
        # не називала). Без нормування ці плями мовчки з'їдали б площу речі в
        # кожному площозалежному правилі.
        _чо = float(к.get("частка") or 0) or (1.0 - д[2])
        _сума = _чо + д[2]
        # КОЖЕН КОЛІР НЕСЕ СВІЙ ПРОВЕНАНС (рядок 141): `outfit.елементи` робить із
        # запису `colors` окремі елементи, і другий колір буває центром вікна, коли
        # перший — вимір (hex другого не узгодився з його словом), або навпаки.
        # Центр вікна `другий_колір` віддає тоді, коли hex слову не відповідає.
        _центр_д = tuple(round(x, 2) for x in _центр_вікна(V.ЛЕКСИКОН[д[0]]))
        _нв_д = (не_вимір_кольору(V.ЛЕКСИКОН[д[0]], д[0], "слово моделі",
                                  " — другий колір з опису фото (hex слову не відповідає)")
                 if tuple(д[1]) == _центр_д else
                 не_вимір_кольору(V.ЛЕКСИКОН[д[0]], д[0], "hex моделі",
                                  " — другий колір (жнива v1: назва кольору, а не вимір)")
                 if _v1 else None)
        r["colors"] = [dict(lab=lab_осн, coverage=round(_чо / _сума, 3),
                            не_вимір=r.get("колір_не_вимір")),
                       dict(lab=д[1], coverage=round(д[2] / _сума, 3), не_вимір=_нв_д)]


def накласти_збагачення(r, зб, спір=None, крамниця=None):
    """Поля опису з фото — у запис каталогу, з провенансом. Слово крамниці, яке
    поле перекрило, лишається поруч із суфіксом `_крамниці`.

    `крамниця` — поле кольору крамниці цілком (усі частини); читає `_назва_кольору`.

    СТАРШИНСТВО НАЗВАНЕ ПОЛЕМ ЗА ПОЛЕМ, А НЕ ОДНИМ ПРАВИЛОМ «фото перше»:
      · колір     — ВИМІР з фото старший за слово, КОЛИ свідки згодні (`колір_спір`,
                    ПЕРЕДАЧА §5); у спорі слово крамниці лишається, а запис
                    несе позначку — модель описувала і сукню замість каблучки;
                    НАЗВА ж і без спору лишається за крамницею, крім тоншого
                    відтінку з фото (`_назва_кольору`, рядок 135);
      · крій      — фото старше за ЗДОГАД ІЗ НАЗВИ і молодше за структурований
                    param крамниці (`крій_джерело`);
      · матеріал  — фото молодше за будь-яке слово крамниці про тканину: склад із
                    бирки ока не потребує;
      · формальність — не старша й не молодша, бо в ключ речі не йде взагалі
                    (звірка внизу);
      · візерунок — фото старше за мовчання й generic «принт» слова і молодше
                    за слово, що НАЗИВАЄ сім'ю мотиву (`візерунок_спір`,
                    `_візерунок_фото`).
    """
    r["збагачення"] = True
    # ── ЩО САМЕ VISION-МОДЕЛЬ ПОБАЧИЛА НА КАДРІ (рядок 44 БЕКЛОГУ) ───────────
    # `збагачення=True` каже лише, що на фото ВЗАГАЛІ щось видно (впевненість ≥
    # `ЗБАГАЧЕННЯ_ПОРІГ`; «річ не видно» — логотип, таблиця розмірів — це рівно 0
    # і сюди не доходить). Воно НЕ каже, що видно саме цю річ: ж-07624 —
    # каблучка, чий опис починається «Сукня темно-зеленого кольору» при
    # впевненості 1.0. Тому кадр судиться тим самим словником слотів, яким код
    # судить саму річ: опис моделі проганяється через `слот` як назву товару.
    # Збіг зі слотом речі — єдиний доказ «на фото та сама річ», який у коді є;
    # розбіжність — навпаки, свідчення проти фото. Поле читає
    # `pipeline.опис_відповідь_з_json` (позначка «фото може не відповідати назві»).
    # ВИМІРЯНО 19.09.2026 на почищеному фіді, по записах зі збагаченням:
    # каталог_повний — 9 478 записів, збіг слота 8 239, розбіжність 1 000, опис
    # без слота 239; каталог_brief — 401 / 235 / 138 / 28.
    r["фото_слот"] = слот({"назва": зб.get("опис") or "", "категорія": ""})
    if спір:
        r["колір_спір"] = спір          # позначка, не мовчання: колір лишився за крамницею
    else:
        _накласти_колір(r, зб, крамниця)
    import silhouette as _S          # ліниво: silhouette → fit → outfit, цикл на імпорті feed
    # ── КРІЙ: ФОТО СТАРШЕ ЗА ЗДОГАД ІЗ НАЗВИ, МОЛОДШЕ ЗА PARAM ───────────────
    # `крій_джерело` розрізняє двох свідків крамниці: «param силует» — це
    # структуроване поле фіду, «слово речі» — здогад `verify.крій_зі_слова` з
    # назви. Фото перекриває здогад і мовчить там, де крамниця сказала прямо.
    # ── R-FP-07: ДВА СВІДКИ КРОЮ ЛЕЖАТЬ ПОРУЧ І НІХТО ЇХ НЕ ЗВІРЯЄ ───────────
    # Корпус (тема-7, R-FP-07): «Nickname-class attributes are the highest-risk
    # output: the reference model's own published failure is a wrong pocket
    # nickname. Require a confidence signal on nickname outputs specifically, or
    # drop the class». Крій — рівно такий атрибут-прізвисько: «bodycon»,
    # «a-line», «wrap» — це НАЗВА форми, а не її вимір. Запасний хід «drop the
    # class» у коді вже є (`verify.крій_зі_слова` віддає None поза лексиконом);
    # бракувало ДРУГОЇ половини — сигналу на конкретному виході.
    # ЩО ТУТ БУЛО. Три рядки нижче кладуть у ту саму річ ДВА свідчення про крій:
    # `крій_крамниці` (слово крамниці) і `крій` із фото, плюс `крій_джерело` й
    # `крій_за_чим`. Обидва лежать поруч, і жоден шар їх не звіряє: `silhouette`
    # бере переможця й переводить його в САНТИМЕТРИ (`КРОЇ[...]`: ease і форма —
    # множники обхвату), тобто прізвисько стає виміром без жодної позначки, що
    # другий свідок казав інше.
    # ВИМІРЯНО на `каталог_повний` (12 328 записів): `крій_крамниці` стоїть на
    # 1 588 речах, і на 1 080 із них слово крамниці РОЗХОДИТЬСЯ з крієм із фото
    # («Сатинові широкі штани зі складками»: крамниця wide, фото bodycon).
    # Загальна `впевненість` запису (`жнива_v2`) тут не рятує: вона про КОЛІР.
    # ЩО СТАЛО. Незгода кладеться позначкою `крій_спір` — тим самим ідіомом, що
    # вже стоїть на візерунку (`візерунок_спір`). Переможця вона НЕ міняє:
    # правило вимагає сигналу впевненості, а не іншого вердикту.
    # ⚠ ТРИ ПОЛЯ ЗНІМАЮТЬСЯ ДО ПЕРЕЗАПИСУ, А НЕ ПІСЛЯ: рядок нижче ставить у
    # `крій`, `крій_джерело` і `крій_за_чим` свідчення ФОТО, і прочитане після
    # нього «за_чим крамниці» було б ["фото"] — тобто позначка спору цитувала б
    # сама себе замість другого свідка.
    _кр_фото = зб.get("крій") if зб.get("крій") in _S.КРОЇ else None
    _кр_крамниці, _свідок = r.get("крій"), r.get("крій_джерело")
    _за_чим_кр = r.get("крій_за_чим")
    if _кр_фото and _свідок in (None, "слово речі"):
        r["крій_крамниці"] = _кр_крамниці
        r["крій"], r["крій_за_чим"], r["крій_джерело"] = _кр_фото, ["фото"], "фото"
    if _кр_фото and _кр_крамниці and _кр_фото != _кр_крамниці:
        r["крій_спір"] = dict(фото=_кр_фото, крамниця=_кр_крамниці,
                              свідок_крамниці=_свідок, за_чим_крамниці=_за_чим_кр,
                              чому="крій прочитано з фото, крамниця каже інше")
    дов = зб.get("довжина")
    if дов and дов in _ДОВЖИНА_ФОТО_ЗА_СЛОТОМ.get(r.get("слот"), ()):
        # ── ЧОМУ ТУТ НЕ ПИШЕТЬСЯ `край_джерело="фото"` ───────────────────────
        # `край_джерело` називає не походження, а РІД свідчення про край:
        # «річ» — сантиметри виробу, «слово» — РІВЕНЬ, який composer переводить
        # у смугу ±`край_розкид_см` на цьому тілі, «дефолт слота» — заглушка.
        # «міді» з фото — рівно той самий рід, що «міді» зі слова: рівень, не
        # сантиметр. Поставити сюди третє значення означало б вивести річ
        # з-під `fit.краї`, де гілка `зі_слова` проганяє смугу п'ятьма точками
        # й обмежує силу до «soft» (T3 ≤ вимір), — тобто мовчки ПОСЛАБИТИ
        # K-FIT-03 до вердикту над точкою. Походження рівня несе
        # `довжина_джерело`, і воно тут і стоїть.
        r["довжина_рівень_крамниці"] = r.get("довжина_рівень")
        r["довжина_рівень"], r["довжина_джерело"] = дов, "фото"
    м = зб.get("матеріал")
    r["матеріал_фото"] = м
    # ── МАТЕРІАЛ: ОКО ЗАХОДИТЬ ЛИШЕ В МОВЧАННЯ ──────────────────────────────
    # Крамниця говорить про тканину двома полями: `матеріал` — цілий склад із
    # бирки («60% віскоза, 40% вовна»), `волокно` — нормалізоване одне слово з
    # назви. Фото не бачить волокна, тому пише лише туди, де МОВЧАТЬ ОБИДВА.
    # `матеріал` у цій умові не зайвий: `формальність._ВІСЬ_ТКАНИНИ` читає
    # `волокно` ПЕРШИМ, тож слово з ока, покладене поруч із наявним складом,
    # не доповнило б його, а витіснило б із осі формальності.
    if м and not r.get("волокно") and not r.get("матеріал"):
        r["волокно"], r["волокно_джерело"] = м, "фото"
    if isinstance(зб.get("блиск"), int) and 0 <= зб["блиск"] <= 3:
        r["блиск_крамниці"] = r.get("блиск")
        r["блиск"], r["блиск_джерело"] = зб["блиск"], "фото"
    вз, за_чим = _візерунок_фото(зб)
    if вз in _КЛАСИ_ФОТО:
        ф_вз = "solid" if вз == "однотонний" else вз
        сл = r.get("візерунок")
        if (r.get("візерунок_джерело") == "слово" and сл not in _НЕ_СІМ_Я_МОТИВУ
                and ф_вз != сл
                and not ((сл in _ДЕКОР_МОТИВУ) != (ф_вз in _ДЕКОР_МОТИВУ)
                         and ф_вз not in _НЕ_СІМ_Я_МОТИВУ)):
            r["візерунок_спір"] = dict(фото=вз, крамниця=сл, за_чим_фото=за_чим,
                                       чому="слово крамниці називає сім'ю мотиву, фото — інше")
        else:
            r["візерунок_крамниці"] = сл
            r["візерунок"] = ф_вз
            r["візерунок_за_чим"], r["візерунок_джерело"] = за_чим, "фото"
    ф = зб.get("формальність")
    # ── ФОРМАЛЬНІСТЬ З ФОТО СТОЇТЬ ОКРЕМО І В КЛЮЧ РЕЧІ НЕ ЙДЕ ──────────────
    # Доти тут стояло `r["формальність"] = ф`, а `outfit.елементи` читає
    # `r.get("формальність") or ТИП_ФОРМАЛЬНІСТЬ[тип]` — тобто бал моделі МОВЧКИ
    # ставав старшим за таблицю типів на кожній описаній речі.
    # ЗВІРЕНО (200 речей, сід 17, 17.09.2026, `проби/zbah_фід.py`): бал із фото
    # лежить усередині `формальність.інтервал_типу` у 53.5 % речей, у межах ±1
    # від нього — у 78.5 %. Полярності `інтервал_формальності` розсувають
    # інтервал щонайбільше на 1 у кожен бік (усі їхні зсуви — 0, −1 або +1), тож
    # і з ними згода не перевищує 78.5 %. Поріг «≥ 80 % — можна брати другою
    # думкою для речей без коду типу» НЕ ВЗЯТО, і поле лишається ОКРЕМИМ: його
    # читає око й прилади, шар формальності — ні.
    if isinstance(ф, int) and 1 <= ф <= 10:
        r["формальність_фото"] = ф
    r["фото_опису"] = зб.get("фото")
    return r


_КЛАСИ_ФОТО = frozenset(V.КЛАСИ_МОТИВУ.values())

# ── ВІЗЕРУНОК З ФОТО: ЛЕОПАРД ЧИТАВСЯ ЯК «КВІТКОВИЙ» (18.09.2026) ────────────
# Спіймано на вето Н-V07-023: `verify.клас_мотиву` на назві «Спідниця шовкова в
# леопардовому принті» дає «анімалістичний», а в пакеті та сама річ стояла
# «квітковий». Нічия довжини коренів у `клас_мотиву` тут НІ ДО ЧОГО — на тексті
# слова (назва + колір + param) вона спрацьовує на 3 речах каталогу, і жодна не
# леопардова. Причина — поле `візерунок` опису з фото перекривало слово крамниці
# БЕЗ УМОВ. ВИМІРЯНО на каталог_повний (10 770 описів, qwen3-vl-8b, жнива v1):
#   · поле моделі не видало «анімалістичний» ЖОДНОГО разу, хоч воно в списку
#     дозволених; приклади промпту — «однотонний, смужка, клітинка, горох,
#     квітковий тощо», і тварину модель кладе в найближчий із них: квітковий 25,
#     принт 9, смужка 6, однотонний 1 — а ВЛАСНЕ поле «опис» тих самих речей
#     каже «з леопардовим принтом», «зебровим», «зміїної шкіри» (41 опис, 0 заперечень);
#   · у 404 описаних речах слово крамниці НАЗИВАЄ сім'ю мотиву, а поле фото
#     каже інше: іншу сім'ю 120, «однотонний» 264, generic «принт» 20. Поглядом
#     на вибірку фото там часто описує ІНШУ річ («Штани лляні … в полоску» →
#     опис «Футболка … однотонна») — той самий дефект, що в кольорі (`колір_спір`).
# Тому два кроки, обидва вузькі:
#   1) тварина — з ОПИСУ: поле її не вміє сказати, опис уміє. Не `клас_мотиву(опис)`:
#      опис рясніє запереченнями («без смуг, клітинки або квітів» — 4 679 описів),
#      і загальне читання дало б 711 хибних «клітинка»; воно ж на «…леопардовим
#      принтом … не має смуг, клітинки» віддає «клітинка» нічиєю довжини. Тож
#      питаються лише корені тварини, клауза з запереченням не рахується;
#   2) слово крамниці, що називає сім'ю, старше за фото; у спорі слово лишається,
#      клас фото — у позначці `візерунок_спір`, не мовчки. Мовчання слова,
#      «однотонний» і generic «принт» фото уточнює, як і раніше.
#      ДЕКОР ПРОТИ ДРУКУ — НЕ СПІР. Мереживо й вишивка (04.09.2026 — шар щільності,
#      не друк) лежать на іншій осі, ніж смужка чи квіти: «Подовжена сорочка в
#      смужку з мереживом» — правда обидва. Перша редакція віддавала тут перемогу
#      слову, і 58 речей міняли клас друку на клас декору, а декор правилам дає
#      менше (`колір_образу.ФОРМА_МОТИВУ` його не знає). Тож фото з сім'єю друку
#      лишається; декор слова старший лише за «однотонний» і generic фото.
# До/після — див. коміт; стенд_знімок --дим і проби K-COL-10/K-PAL-07/K-PAL-10/
# K-ACC-13/K-CRA-10/zbah_фід звірено.
_НЕ_СІМ_Я_МОТИВУ = (None, "solid", "принт")
_ДЕКОР_МОТИВУ = ("мереживо", "вишивка")
_КОРЕНІ_ТВАРИНИ = tuple(k for k, v in V.КЛАСИ_МОТИВУ.items() if v == "анімалістичний")
_ЗАПЕРЕЧЕННЯ_МОТИВУ = re.compile(r"(?:^|\s)(?:без|не|ні|немає|жодн\w*)(?=\s|$)")


def _візерунок_фото(зб):
    """(клас, за_чим) опису з фото: поле моделі, а тварина — з її власного опису."""
    вз = зб.get("візерунок")
    if вз != "анімалістичний":
        for кл in re.split(r"[.,;:—]", (зб.get("опис") or "").lower()):
            к = next((k for k in _КОРЕНІ_ТВАРИНИ if V._на_межі(k, кл)), None)
            if к and not _ЗАПЕРЕЧЕННЯ_МОТИВУ.search(кл):
                return "анімалістичний", ["фото: опис «%s»" % к, "поле фото: %s" % вз]
    return вз, ["фото"]
