"""Плитки, вікна вибраної гілки ядра та старого добору, на трьох записаних профілях."""
import json
import sys
from pathlib import Path
import bridge
from colorspace import hx
from feed import підходить
from міст_пакет import вікна_пакета
from портрет_вхід import збірка
from face_features import джерело_виміру
from реєстр_намір import ТИПОВИЙ_НАМІР
from slots import СЛОТИ_ПАКЕТА
from ядро.палітра_дня import портрет_і_палітра
from ядро.ситуація import Ситуація

КОРІНЬ = Path(sys.argv[1])
СТЕНД = json.loads(Path('стенд_вх.json').read_text())
НАЗВИ = ('темна хвоя', 'чорнослив', 'капучино')

def профілі():
    yield 'стенд', СТЕНД
    for ід in ('ж1', 'ж3'):
        д = json.loads((КОРІНЬ / 'аудит/проби/жінки' / (ід + '.json')).read_text())
        yield ід, dict(СТЕНД, шкіра=д['skin'], волосся=д['hair'], очі=д['eyes'], очі_кільце=д.get('ring'))

def палітри(вхід):
    return json.loads(bridge.виклик('палітри', json.dumps(вхід, ensure_ascii=False)))

def main():
    результат = []
    for ід, д in профілі():
        ф = збірка(д, лише_палітра=True)[0]
        основи = палітри(д)['основи']
        за = {o['відтінок']: o for ряд in ('рекомендовані','інші') for o in основи[ряд] if o.get('відтінок')}
        профіль = {ключ: д.get(ключ) for ключ in ('шкіра', 'волосся', 'очі')}
        профіль['кільце'] = д.get('очі_кільце')
        for назва in НАЗВИ:
            о = за[назва]
            вибір = dict(база=о['ключ'], база_hex=о['hex'], база_назва=назва, база_тип='колір', насиченість='середні')
            for г in палітри(dict(д, вибір_кольору=вибір))['гілки']:
                схема = г['схема']
                _, план = портрет_і_палітра({"профіль":{"колір":профіль,
                    "палітра":{"схема": схема, "вибір_кольору": вибір}}}, Ситуація(1))
                assert план['дані']['scheme'] == схема, (схема, план['дані'])
                вікна = план['вікна']
                _, _, _, _, старі = вікна_пакета(ф, {'палітри':{'розвилка':[{'схема':схема}]}}, 0, СЛОТИ_ПАКЕТА,
                    {'вибір_кольору':вибір,'source':джерело_виміру(ф),'самозвіт':{},'намір':ТИПОВИЙ_НАМІР})
                кольори = г.get('зразки', [])
                результат.append(dict(профіль=ід, основа=назва, схема=схема, якір=г.get('якір_основи'),
                    основа_поза_вікнами=г.get('основа_поза_вікнами'),
                    зразки=кольори, підміна=г.get('запасний_прийом'),
                    у_вікнах=[к for к in кольори if any(підходить(hx(к), в) for в in вікна)],
                    у_старих_вікнах=[к for к in кольори if any(підходить(hx(к), в) for в in старі)]))
    print(json.dumps(результат, ensure_ascii=False, indent=2))

if __name__ == '__main__':
    main()
