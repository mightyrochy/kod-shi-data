def головна():
    """Обирає явний збір або відтворення зі знімка і пише три результати."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--зібрати", action="store_true")
    парсер.add_argument("--оновити-історію", action="store_true")
    парсер.add_argument("--знімок", type=Path)
    парсер.add_argument("--причини", action="store_true",
                        help="зі --знімок: дописати причини з тек обміну, прогонів (якщо доступні) і журналу ОС")
    парсер.add_argument("--вихід", type=Path, default=Path(__file__).resolve().parent)
    парсер.add_argument("--історія", type=Path, default=Path(__file__).resolve().with_name("історія_1856.json"))
    парсер.add_argument("--запуски", type=Path, default=Path.home() / "gemini-runs")
    парсер.add_argument("--сесії", type=Path, default=Path.home() / ".codex/sessions")
    парсер.add_argument("--журнали-agy", dest="журнали", type=Path, default=Path.home() / ".gemini/antigravity-cli/log")
    парсер.add_argument("--обмін", type=Path, default=Path("C:/Users/Public/gemini/out"))
    параметри = парсер.parse_args()
    параметри.вихід.mkdir(parents=True, exist_ok=True)
    if параметри.оновити_історію:
        зняти_історію(параметри.історія)
    if параметри.зібрати or параметри.причини:
        if параметри.зібрати:
            дані = зібрати(параметри)
        elif параметри.знімок:
            # Знімок, знятий до причин: їх дописують з тек, що досі є, тим самим кодом, що й під час збору.
            дані = прочитати(параметри.знімок)
            дані["події_ОС"] = події_ос()
            додати_причини(дані["запуски"], параметри.обмін,
                           параметри.запуски if параметри.запуски.is_dir() else None, дані["події_ОС"])
        else:
            парсер.error("--причини — лише зі --знімок")
        (параметри.вихід / "джерела.json").write_text(json.dumps(дані, ensure_ascii=False, sort_keys=True, indent=2) + "\n", encoding="utf-8", newline="\n")
    elif параметри.знімок:
        дані = прочитати(параметри.знімок)
    else:
        парсер.error("потрібно --зібрати або --знімок")
    записати_csv(параметри.вихід / "запуски.csv", дані["запуски"])
    записати_csv(параметри.вихід / "квота.csv", дані["квота"])
    записати_csv(параметри.вихід / "agy_cli.csv", дані["agy_cli"])
    (параметри.вихід / "звірка.md").write_text(звіт(дані), encoding="utf-8", newline="\n")
    print(f"Запусків: {len(дані['запуски'])}; зчитувань квоти: {len(дані['квота'])}; позначок: {len(дані['позначки'])}")


if __name__ == "__main__":
    головна()
