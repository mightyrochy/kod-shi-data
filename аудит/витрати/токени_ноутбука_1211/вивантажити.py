"""Вивантажує числові метадані запусків і квоти без текстів розмов та секретів.

Збір: python вивантажити.py --зібрати --оновити-історію
Повтор без доступу до ноутбука: python вивантажити.py --знімок джерела.json
Потрібен лише Python 3.11+; для явного оновлення історії потрібен gh із доступом на читання.
"""

import argparse
import collections
import csv
import datetime
import json
from pathlib import Path
import re
import subprocess


UTC = datetime.timezone.utc
МІСЦЕВИЙ = datetime.timezone(datetime.timedelta(hours=2))
ПОЧАТОК = datetime.datetime(2026, 11, 5, tzinfo=UTC)
КІНЕЦЬ = datetime.datetime(2026, 11, 12, tzinfo=UTC)
ЛІЧИЛЬНИКИ = ("input_tokens", "cached_input_tokens", "output_tokens",
              "reasoning_output_tokens", "total_tokens")
ПОЛЯ = ("вхід", "кеш", "вихід", "міркування", "разом")
ІДЕНТИФІКАТОР = re.compile(r"2026\d{4}-\d{6}-[a-f0-9]{12}")
ПОЗНАЧКА = re.compile(r"gemini-queue/[^\s|`<>\";,:()]+/[^\s/|`<>\";,:()]+/\d+(?:/[^\s|`<>\";,:()]+)?")
ГРУПИ = ("GEMINIMODELS", "CLAUDEANDGPTMODE", "GEMINI4ARGON")
ОБГОРТКА = Path(__file__).resolve().parents[2] / "адаптери/gemini/gemini_run.ps1"
МЕЖА_ПРИЧИНИ = 240  # знаків: ConvertTo-NoteText обгортки, межа рядка #1856


def час(значення, місцевий=False):
    """Повертає UTC; беззонні мітки обгортки трактує як час Києва після 25.10."""
    if not значення or значення in ("?", "—", "-"):
        return None
    if isinstance(значення, (int, float)):
        return datetime.datetime.fromtimestamp(значення, UTC)
    try:
        дата = datetime.datetime.fromisoformat(str(значення).replace("Z", "+00:00"))
        return дата.replace(tzinfo=МІСЦЕВИЙ if місцевий else UTC).astimezone(UTC) if дата.tzinfo is None else дата.astimezone(UTC)
    except ValueError:
        return None


def мітка(дата):
    """Форматує UTC без залежності від локалі системи."""
    return дата.isoformat(timespec="microseconds").replace("+00:00", "Z") if дата else ""


def у_вікні(дата):
    """Перевіряє напіввідкритий інтервал обліку."""
    return дата is not None and ПОЧАТОК <= дата < КІНЕЦЬ


def час_теки(ід):
    """Читає місцевий час із назви теки, а не з Unix-поля time у worker.json."""
    return час(datetime.datetime.strptime(ід[:15], "%Y%m%d-%H%M%S").isoformat(), True)


def прочитати(шлях):
    """Читає JSON, не виводячи його вміст у журнал."""
    return json.loads(шлях.read_text(encoding="utf-8-sig"))


def класи_кодів(шлях=ОБГОРТКА):
    """Читає таблицю «код кінця → клас причини» з обгортки — одне джерело для cause.json і старих записів без нього."""
    тіло = re.search(r"\$script:CauseOfCode = @\{(.*?)\n\}", шлях.read_text(encoding="utf-8-sig"), re.S)
    return dict(re.findall(r"([A-Z0-9_]+) = '([^']+)'", тіло[1]))


def один_рядок(текст):
    """Текст причини як у ConvertTo-NoteText обгортки: один рядок без керівних символів, до межі рядка #1856."""
    return re.sub(r"[\x00-\x1f\x7f]+", " ", текст).strip()[:МЕЖА_ПРИЧИНИ]


def події_ос():
    """Старти (Kernel-General 12) і зупинки (13) ОС з журналу System; журнал недоступний — порожньо, не вигадано."""
    запит = ("Get-WinEvent -FilterHashtable @{LogName='System';ProviderName='Microsoft-Windows-Kernel-General';Id=12,13;"
             "StartTime=[datetime]'" + (ПОЧАТОК - datetime.timedelta(days=1)).strftime("%Y-%m-%d") + "'} -ErrorAction Stop | "
             "ForEach-Object { '{0} {1}' -f $_.Id, $_.TimeCreated.ToUniversalTime().ToString('o') }")
    try:
        вивід = subprocess.run(["powershell.exe", "-NoProfile", "-Command", запит], capture_output=True,
                               encoding="utf-8", errors="replace", check=True).stdout
    except (OSError, subprocess.CalledProcessError):
        return []
    return sorted(({"подія": "старт" if рядок.split()[0] == "12" else "зупинка", "час_UTC": мітка(час(рядок.split()[1]))}
                   for рядок in вивід.splitlines() if re.fullmatch(r"1[23] \S+", рядок.strip())), key=lambda п: п["час_UTC"])


def зупинка_між(ос, від, до):
    """Перша зупинка ОС у (від, до]; до=None — перша після від, якщо до неї ОС не стартувала знову."""
    for подія in sorted(ос, key=lambda п: п["час_UTC"]):
        мить = час(подія["час_UTC"])
        if мить <= від:
            continue
        if до is None and подія["подія"] == "старт":
            return None
        if подія["подія"] == "зупинка" and (до is None or мить <= до):
            return подія["час_UTC"]
    return None


def назва_позначки(стан):
    """Позначка черги зі стану в теці обміну."""
    return "gemini-queue/{slug}/{model}/{n}".format(**стан) + ("/" + стан["cond"] if стан.get("cond") else "")


def рядок_звіту(рядок):
    """Рядок без Markdown-обрамлення (`**…**`, зворотні лапки) — те саме правило, що `Get-ReportLine` обгортки
    (gemini_run.ps1): звіт із «**ЗАБЛОКОВАНО: …**» обгортка приймає як BLOCKED, тож і причину шукають у ньому так само."""
    return рядок.strip().strip("`* ")


def причина(з, стан, запис, хвіст, повтор, іде, ос, класи):
    """Клас, текст і джерело причини кінця запуску; DONE і запуск, що ще йде, — без класу.

    cause.json обгортки — перший; для старших записів той самий клас дає таблиця кодів обгортки, а BLOCKED — рядок
    «ЗАБЛОКОВАНО» звіту ролі. Чого код не визначає — «невідомо», не вгадано.
    """
    if запис:
        return запис.get("class", ""), запис.get("text", ""), "cause.json"
    код = з["код"]
    if код == "DONE":
        return "", "", "код кінця"
    if код == "НЕМАЄ_КОДУ" and стан and стан.get("code"):
        return "", "іде у мить вивантаження; кінець пізніше — " + стан["code"], "стан у теці обміну"
    if стан and стан.get("code") == "":
        # Порожній код лишає лише зупинка конвеєра ззовні (catch не біжить, finally — так): Get-RunCause обгортки.
        зупинка = зупинка_між(ос, час(стан.get("ended_utc")), None)
        return "ноутбук і обгортка", "код кінця порожній: процес наряду зупинено ззовні" + (
            "; наступна зупинка ОС " + зупинка if зупинка else ""), "код кінця"
    if код == "НЕМАЄ_КОДУ":
        if повтор:
            return "квота", "QUOTA посеред прогону: позначка чекає скидання " + повтор, "QUOTA_ZERO повтору"
        if іде:
            return "", "іде у мить вивантаження", "стан позначки"
        return "невідомо", "нема запису кінця" + ("" if з["стадія"] == "сесія моделі" else "; модель не стартувала"), "—"
    if код == "ПОЗА_ЗІСТАВЛЕННЯМ":
        return "невідомо", "сесія Codex без запуску обгортки", "—"
    клас, текст = класи.get(код, "невідомо"), код
    if код == "BLOCKED":
        рядки = [р for р in map(рядок_звіту, хвіст.splitlines()) if р.startswith("ЗАБЛОКОВАНО")]
        клас, текст = (клас, рядки[-1]) if рядки else ("невідомо", "BLOCKED без рядка ЗАБЛОКОВАНО")
        if текст.startswith("ЗАБЛОКОВАНО: LIVE_AFTER_INVALID"):
            клас = "модель"
    if код == "NO_REPORT":
        клас, текст = "невідомо", "NO_REPORT: чи звіт не прийнято, старий запис не каже"
    if код == "INTERRUPTED":
        зупинка = зупинка_між(ос, час(з["початок_UTC"]), час(з["кінець_UTC"]))
        текст = "INTERRUPTED: " + ("зупинка ОС " + зупинка if зупинка else "процес наряду зник; зупинки ОС у журналі за прогін нема")
    return клас, один_рядок(текст), "код кінця"


def додати_причини(запуски, вихідні, корінь, ос):
    """Дописує кожному запуску клас, текст і джерело причини з тек обміну й прогонів."""
    класи = класи_кодів()
    повтори = collections.defaultdict(list)
    for шлях in sorted(вихідні.glob("2026*.json")):
        if ІДЕНТИФІКАТОР.fullmatch(шлях.stem):
            стан = прочитати(шлях)
            # Квота посеред прогону пише стан під новим ід із полем retake (Enter-RunQuotaWait), а не кінець прогону.
            if стан.get("code") == "QUOTA_ZERO" and "retake" in стан and стан.get("slug"):
                повтори[назва_позначки(стан)].append((час_теки(шлях.stem), стан.get("qgroup", "")))
    ідуть = set()
    for шлях in sorted((вихідні / "marker-state").glob("*.txt")):
        текст = шлях.read_text(encoding="utf-8-sig", errors="replace")
        if текст.startswith("STARTED {"):
            ідуть.add(json.loads(текст[8:]).get("id", ""))
    старти = collections.defaultdict(list)
    for з in запуски:
        старти[з["позначка"]].append(час(з["початок_UTC"]))
    for з in запуски:
        шлях = вихідні / (з["ід"] + ".json")
        стан = прочитати(шлях) if шлях.exists() else {}
        запис = корінь / з["ід"] / "cause.json" if корінь else None
        запис = прочитати(запис) if запис and запис.exists() else {}
        хвіст = вихідні / (з["ід"] + ".tail.txt")
        хвіст = хвіст.read_text(encoding="utf-8-sig", errors="replace") if хвіст.exists() else ""
        початок = час(з["початок_UTC"]).replace(microsecond=0)
        наступний = min([с for с in старти[з["позначка"]] if с > час(з["початок_UTC"])], default=None)
        повтор = [г for мить, г in повтори.get(з["позначка"], []) if мить >= початок and (наступний is None or мить < наступний)]
        з["клас_причини"], з["причина"], з["джерело_причини"] = причина(
            з, стан, запис, хвіст, (повтор[0] or "без групи") if повтор else "", з["ід"] in ідуть, ос, класи)


def події(шлях, режим=""):
    """Читає JSONL по рядках; неповний останній рядок не видає за подію."""
    with шлях.open(encoding="utf-8-sig", errors="replace") as потік:
        for номер, рядок in enumerate(потік, 1):
            if режим == "сесії":
                шапка = re.match(r'\{"timestamp":\s*"([^"]+)",\s*"type":\s*"([^"]+)"', рядок[:256])
                if шапка and шапка[2] not in ("session_meta", "turn_context"):
                    if шапка[2] != "event_msg" or not re.search(r'"payload":\s*\{"type":\s*"token_count"', рядок[:256]):
                        yield номер, {"timestamp": шапка[1]}
                        continue
            elif режим == "codex":
                шапка = re.match(r'\{"type":\s*"([^"]+)"', рядок[:128])
                if шапка and шапка[1] not in ("thread.started", "turn.completed"):
                    continue
            try:
                yield номер, json.loads(рядок)
            except json.JSONDecodeError:
                yield номер, None


def додати(ліворуч, праворуч):
    """Додає однойменні числові лічильники."""
    return [а + б for а, б in zip(ліворуч, праворуч)]


def лічильники(вхід):
    """Нормалізує дві схеми usage без додавання кешу чи міркувань удруге."""
    if not isinstance(вхід, dict) or "input_tokens" not in вхід:
        return None
    return [вхід.get("input_tokens", 0), вхід.get("cached_input_tokens", вхід.get("cache_read_tokens", 0)),
            вхід.get("output_tokens", 0), вхід.get("reasoning_output_tokens", вхід.get("thinking_tokens", 0)),
            вхід.get("total_tokens", вхід.get("input_tokens", 0) + вхід.get("output_tokens", 0))]


def квота(дата, рушій, група, вікно, залишок, скидання, джерело, примітка=""):
    """Створює рядок із дозволених числових метаданих квоти."""
    return {"час_UTC": мітка(дата), "рушій": рушій, "група": група, "вікно": вікно,
            "залишок_відсотків": залишок, "скидання_UTC": мітка(час(скидання)),
            "джерело": джерело, "примітка": примітка}


def зняти_історію(шлях):
    """Зберігає лише таблицю квоти та назви позначок з усіх доступних правок #1856."""
    запит = '''query($cursor:String) { repository(owner:"mightyrochy",name:"kod-shi-data") {
      issue(number:1856) { userContentEdits(first:100,after:$cursor) { totalCount
        nodes { editedAt deletedAt diff } pageInfo { hasNextPage endCursor } } } } }'''
    курсор = None
    правки = []
    while True:
        команда = ["gh", "api", "graphql", "-f", "query=" + запит]
        if курсор:
            команда += ["-f", "cursor=" + курсор]
        відповідь = subprocess.run(команда, capture_output=True, encoding="utf-8", check=True)
        дані = json.loads(відповідь.stdout)
        if дані.get("errors"):
            raise RuntimeError("GitHub не повернув історію #1856")
        сторінка = дані["data"]["repository"]["issue"]["userContentEdits"]
        for запис in сторінка["nodes"]:
            дата = час(запис["editedAt"])
            тіло = запис.get("diff") or ""
            рядки = []
            for рядок in тіло.splitlines():
                клітинки = [к.strip() for к in рядок.split("|")[1:-1]]
                if len(клітинки) != 5 or not re.fullmatch(r"(?:agy · [A-Z0-9]+|codex · остання відмова)", клітинки[0]):
                    continue
                if not re.fullmatch(r"\d+(?:\.\d+)? %", клітинки[2]):
                    continue
                if not час(клітинки[4]):
                    continue
                рядки.append(квота(час(клітинки[4]), клітинки[0].split(" · ")[0],
                                   клітинки[0].split(" · ")[1] if клітинки[0].startswith("agy") else "CODEX",
                                   клітинки[1] if клітинки[1] in ("WEEK", "5H", "DAY") else "REFUSAL",
                                   float(клітинки[2].split()[0]), клітинки[3], "issue1856",
                                   "відмова; тип вікна невідомий" if клітинки[0].startswith("codex") else ""))
            правки.append({"час_редагування": мітка(дата), "видалено": bool(запис.get("deletedAt")),
                           "квота": рядки, "позначки": sorted(set(ПОЗНАЧКА.findall(тіло)))})
        if not сторінка["pageInfo"]["hasNextPage"]:
            break
        курсор = сторінка["pageInfo"]["endCursor"]
    шлях.write_text(json.dumps({"доступно_правок": сторінка["totalCount"], "правки": правки},
                              ensure_ascii=False, sort_keys=True, indent=2) + "\n", encoding="utf-8", newline="\n")


def зібрати_сесії(корінь):
    """Знімає прирости token_count й усі rate_limits, не читаючи тексти розмов у результат."""
    сесії = []
    заміри = []
    for шлях in sorted(корінь.rglob("*.jsonl")):
        запис = {"ід": "", "прогін": "", "модель": "", "гілка": "", "початок": "", "кінець": "",
                 "токени": None, "токени_вікна": None, "подій_лічильника": 0, "відкати": 0, "пошкоджених_рядків": 0}
        попередні = [0] * 5
        сума = [0] * 5
        сума_вікна = [0] * 5
        останній = None
        початок = None
        for номер, подія in події(шлях, "сесії"):
            if подія is None:
                запис["пошкоджених_рядків"] += 1
                continue
            дата = час(подія.get("timestamp"))
            if дата:
                останній = дата
            тип = подія.get("type")
            дані = подія.get("payload") or {}
            if тип == "session_meta":
                початок = час(дані.get("timestamp")) or дата
                запис["ід"] = дані.get("id", "")
                збіг = ІДЕНТИФІКАТОР.search(дані.get("cwd", ""))
                запис["прогін"] = збіг.group() if збіг else ""
                запис["гілка"] = (дані.get("git") or {}).get("branch", "")
                if початок and початок >= КІНЕЦЬ and (not збіг or час_теки(збіг.group()) >= КІНЕЦЬ):
                    break
            elif тип == "turn_context":
                запис["модель"] = дані.get("model", запис["модель"])
            elif тип == "event_msg" and дані.get("type") == "token_count":
                облік = дані.get("info") or {}
                поточні = лічильники(облік.get("total_token_usage"))
                if поточні is not None:
                    приріст = [а - б for а, б in zip(поточні, попередні)]
                    if any(а < 0 for а in приріст):
                        запис["відкати"] += 1
                        # При скиданні історії cumulative уже не є продовженням старої шкали.
                        приріст = лічильники(облік.get("last_token_usage")) or [0] * 5
                    сума = додати(сума, приріст)
                    if у_вікні(дата):
                        сума_вікна = додати(сума_вікна, приріст)
                    попередні = поточні
                    запис["подій_лічильника"] += 1
                обмеження = дані.get("rate_limits") or {}
                for ключ in ("primary", "secondary"):
                    межа = обмеження.get(ключ)
                    if межа and дата and у_вікні(дата) and "used_percent" in межа:
                        заміри.append(квота(дата, "codex", обмеження.get("limit_id") or "codex",
                                           str(межа.get("window_minutes", "")) + "MIN",
                                           100 - межа["used_percent"], мітка(час(межа.get("resets_at"))),
                                           "codex/" + запис["ід"] + ":" + str(номер), ключ))
        if початок and останній and останній >= ПОЧАТОК and (початок < КІНЕЦЬ or
                (запис["прогін"] and час_теки(запис["прогін"]) < КІНЕЦЬ)):
            запис["початок"], запис["кінець"] = мітка(початок), мітка(останній)
            if запис["подій_лічильника"]:
                запис["токени"], запис["токени_вікна"] = сума, сума_вікна
            сесії.append(запис)
    return сесії, заміри


def зібрати_обгортку(корінь):
    """Читає часові мітки, коди кінця, нульову квоту й видимі позначки з wrapper.log."""
    початки, кінці, коди, позначки, заміри = {}, {}, {}, set(), []
    for номер, рядок in enumerate((корінь / "wrapper.log").read_text(encoding="utf-8-sig").splitlines(), 1):
        дата = час(рядок[:19], True)
        if у_вікні(дата):
            позначки.update(ПОЗНАЧКА.findall(рядок))
        збіг = re.search(r"наряд gemini-queue/.* -> (2026\d{4}-\d{6}-[a-f0-9]{12}) \(слот", рядок)
        if збіг:
            початки[збіг[1]] = мітка(дата)
        збіг = re.search(r"\[(2026\d{4}-\d{6}-[a-f0-9]{12})\]: ([A-Z0-9_]+), ходів", рядок)
        if збіг:
            кінці[збіг[1]], коди[збіг[1]] = мітка(дата), збіг[2]
        збіг = re.search(r"група ([A-Z0-9]+) на 0 %, чекає до ([0-9TZ:-]+)", рядок)
        if збіг and у_вікні(дата):
            заміри.append(квота(дата, "codex" if збіг[1] == "CODEX" else "agy", збіг[1], "MIN_SELECTED", 0, збіг[2],
                               "wrapper.log:" + str(номер), "мінімум вікон; можливий кеш"))
    return початки, кінці, коди, позначки, заміри


def зібрати_потік(шлях, рушій):
    """Знімає ID сесій та usage завершених ходів; step_update не додає до result повторно."""
    сесії = []
    результати = {} if рушій == "agy" else []
    покриті = {}
    кроки = {}
    розмова = ""
    пошкоджено = 0
    if not шлях.exists():
        return сесії, None, 0, 0
    for _, подія in події(шлях, "codex" if рушій == "codex" else ""):
        if подія is None:
            пошкоджено += 1
            continue
        if рушій == "codex":
            if подія.get("type") == "thread.started":
                сесії.append(подія["thread_id"])
            if подія.get("type") == "turn.completed" and подія.get("usage"):
                результати.append(лічильники(подія["usage"]))
        else:
            if подія.get("event") == "init":
                розмова = подія.get("conversation_id", "")
                if розмова and розмова not in сесії:
                    сесії.append(розмова)
            крок = подія.get("step_update") or {}
            if крок.get("usage"):
                кроки[(розмова, крок.get("step_index"))] = лічильники(крок["usage"])
            результат = подія.get("result") or {}
            if результат.get("usage"):
                ід = результат.get("conversation_id") or розмова
                результати[ід] = лічильники(результат["usage"])
                покриті[ід] = {к for к in кроки if к[0] == ід}
    if рушій == "agy":
        # num_turns=2 містить і перший хід: беремо останній result кожної розмови.
        вектори = list(результати.values()) + [в for к, в in кроки.items() if к not in покриті.get(к[0], set())]
    else:
        вектори = результати
    сума = None
    for вектор in вектори:
        if вектор is not None:
            сума = додати(сума or [0] * 5, вектор)
    return сесії, сума, len(результати), пошкоджено


def зібрати_cli(корінь):
    """Рахує всі локальні журнали agy та виклики /usage, не копіюючи їхній текст."""
    журнал = []
    заміри = []
    for шлях in sorted(корінь.glob("cli-*.log")):
        збіг = re.fullmatch(r"cli-(\d{8})_(\d{6})\.log", шлях.name)
        if not збіг:
            continue
        дата = час(datetime.datetime.strptime(збіг[1] + збіг[2], "%Y%m%d%H%M%S").isoformat(), True)
        if дата < ПОЧАТОК - datetime.timedelta(days=1) or дата >= КІНЕЦЬ:
            continue
        текст = шлях.read_text(encoding="utf-8", errors="replace")
        модель = re.search(r'Print mode: starting .*?model="([a-z0-9.-]+)"', текст)
        час_зчитування = None
        for рядок in текст.splitlines():
            if "running slash command /usage" in рядок:
                шапка = re.match(r"[IWEF](\d{2})(\d{2}) (\d{2}:\d{2}:\d{2}(?:\.\d+)?)", рядок)
                if шапка:
                    час_зчитування = час(f"2026-{шапка[1]}-{шапка[2]}T{шапка[3]}", True)
        зчитування = у_вікні(час_зчитування)
        if not у_вікні(дата) and not зчитування:
            continue
        журнал.append({"журнал": шлях.name, "початок_UTC": мітка(дата),
                       "модель": модель[1] if модель else "", "виклик_usage": зчитування,
                       "час_usage_UTC": мітка(час_зчитування),
                       "помилка_usage": "/usage failed:" in текст})
        if зчитування:
            заміри.append(квота(час_зчитування, "agy", "ALL", "UNKNOWN", "", "", "agy/" + шлях.name,
                               "помилка /usage; числової відповіді немає" if "/usage failed:" in текст else "виклик /usage; числової відповіді в цьому журналі немає"))
    return журнал, заміри


