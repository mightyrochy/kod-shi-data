import re
КОРІНЬ_ПРОДУКТУ=re.compile(r'(^|[\s:(/-])(Е[123]|E[123]|е[123]|e[123]|Річ|rich|ПС-|2\.1\d|5\.3|nariad-e3)',re.I)
def вид(n):
    """Вид роботи за назвою наряду (позначка обгортки) чи назвою сесії Claude."""
    if re.search(r'^(ПЕРЕВІРКА|Перевірка|перевірка|Пачка перевірки|Люстерко перевірка|ОГЛЯД|автоперевірка|вердикт|оцінка-автоживого|Оцінка живого|Люстерко оцінка)|огляд звірки',n): return 'перевірка'
    if re.search(r'^(Менеджер|Новий менеджер|Люстерка менеджер)',n): return 'координація: менеджер'
    if re.search(r'^(Диспетчер|ДИСПЕТЧЕР|Люстерка ДИСПЕТЧЕР)',n): return 'координація: диспетчер'
    if re.search(r'автоживий-нова-база',n): return 'живий прогін'
    if re.search(r'(^автоживий|^[Жж]ивий|нічний-живий|Е3-наживо|Е3-показ|^Стенд у браузері|^Шуба)',n): return 'живий прогін'
    if re.search(r'(доробка|продовження|доповнення)',n,re.I): return 'доробка'
    if re.search(r'([Оо]бгортк|^хук-|: хук-|^gpu-|ланцюг|РЕМОНТ|ВИМКНИ|Disk space|публікація-збірки)',n): return 'обгортка'
    if re.search(r'ПК-',n): return 'корінь процесу'
    if re.search(r'(^CI|CI-|храповик|[Лл]ічба.проб|лічба-проб|хеш|чистка-записів|[Дд]ошка-|вимір-сторожів|^Д\d+:|main червоний|ci-журнал|проби-оцінка|фото-видиме)',n): return 'CI й прилади'
    if re.search(r'(Приховані|Подібні)',n): return 'розвідка коренів'
    if КОРІНЬ_ПРОДУКТУ.search(n) or re.search(r'^(Е[123]|Річ|ПС-)',n):
        return 'корінь продукту: прилад' if re.search(r'(^Прилад|прилад)',n) else 'корінь продукту: крок'
    if re.search(r'(В\.2|[Рр]озбір|рішення менеджера)',n): return 'процес'
    return 'інше'
def про_корінь_продукту(n):
    return bool(КОРІНЬ_ПРОДУКТУ.search(n) or re.search(r'^(Е[123]|Річ|ПС-)',n) or re.search(r'Прилад \(.\): (Е|Річ)',n))
