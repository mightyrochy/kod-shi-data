#!/usr/bin/env python3
"""Д.1. Відтворюваний розбір; лише читання git, дошки й джерел.

Із кореня: python3 аудит/дошка_розбір_chatgpt/розбір.py --вихід /tmp/д1
Ручні судження беруться з розмітка.json; евристика історії не є доказом причини.
"""
import argparse
from collections import Counter
import csv
import hashlib
import json
from pathlib import Path
import random
import re
import subprocess

ТЕКА = Path(__file__).resolve().parent
КОРІНЬ = ТЕКА.parents[1]
БАЗА = "adf4317ad1da66e2c07aba829bf475725e8b1556"
ДОШКА = "аудит/БЕКЛОГ.md"
НОМЕР = re.compile(r"^\| *(\d+) *\|")
МЕЖА = re.compile(r"(?<!\\)\|")


def git(*args):
    return subprocess.check_output(
        ["git", *args], cwd=КОРІНЬ, text=True, encoding="utf-8"
    )


def чисто(т):
    return re.sub(r"[*_`]", "", т).strip()


def читати(текст):
    рядки = []
    for лінія, текст_рядка in enumerate(текст.splitlines(), 1):
        if not НОМЕР.match(текст_рядка):
            continue
        клітини = [к.strip() for к in МЕЖА.split(текст_рядка)[1:]]
        if not клітини[-1]:
            клітини.pop()
        if len(клітини) < 4:
            raise ValueError(f"Рядок {лінія}: немає клітинки стану")
        рядки.append({
            "номер": int(клітини[0]), "лінія": лінія,
            "джерело": клітини[1], "вага": клітини[2],
            "стан": клітини[3], "доказ": " | ".join(клітини[4:]),
            "клітинок": len(клітини), "повний": текст_рядка,
        })
    assert len({р["номер"] for р in рядки}) == len(рядки), "Повтор номера"
    return рядки


def стан(рядок, поправки):
    н = str(рядок["номер"])
    if н in поправки:
        return поправки[н]["стан"]
    т = чисто(рядок["стан"])
    for початок, клас in [
        ("ЗАКРИТО", "закрито"), ("ВІДКРИТО", "відкрито"),
        ("ЧАСТКОВО", "частково"), ("ВІДКЛАДЕНО", "відкладено"),
        ("ДУБЛЬ", "дубль"), ("дубль", "дубль"),
        ("ЗНЯТО", "знято"), ("НЕ ", "не_задача"),
        ("ВИМІР, НЕ ДЕФЕКТ", "не_задача"), ("ДО ВІДОМА", "спостереження"),
        ("ЗЛИТО", "закрито"), ("ЗРОБЛЕНО", "закрито"),
        ("ЗАСТАРІЛО", "знято"),
    ]:
        if т.startswith(початок):
            return клас
    return "неясний_стан"


def евристика(р, корені):
    """Лише пошуковий індекс історичних рядків; не додає їх до обіцянок закриття."""
    текст = (р["джерело"] + " " + р["доказ"]).lower()
    оцінки = {}
    ознаки = {}
    for код, к in корені.items():
        збіги = [с for с in к.get("пошук", []) if с.lower() in текст]
        if збіги:
            оцінки[код] = sum(3 if "." in с or "_" in с else 1 for с in збіги)
            ознаки[код] = збіги
    if not оцінки:
        return "БЕЗ", ""
    код = max(оцінки, key=lambda к: (оцінки[к], к))
    return код, "; ".join(ознаки[код])


def історія(база):
    """Перший батько main: PR-сквош — подія запису, НЕ авторство дефекту."""
    текст = git(
        "log", "--reverse", "--first-parent", "--format=@@%H\t%cs\t%s",
        "-p", "--no-renames", база, "--", ДОШКА
    )
    відомі, події = {}, []
    ша = дата = назва = ""
    додані, видалені = {}, {}

    def зберегти():
        for н, р in додані.items():
            ст = чисто(р["стан"])
            було = видалені.get(н)
            попередній = чисто(було["стан"]) if було else ""
            х = відомі.setdefault(н, {
                "номер": н, "поява_sha": ша, "поява_дата": дата,
                "поява_коміт": назва, "перше_закриття_sha": "",
                "повторних_відкриттів": 0, "змін_стану": 0,
            })
            if ст.startswith("ЗАКРИТО") and not х["перше_закриття_sha"]:
                х["перше_закриття_sha"] = ша
            if попередній and попередній != ст:
                х["змін_стану"] += 1
                if попередній.startswith("ЗАКРИТО") and ст.startswith(("ВІДКРИТО", "ЧАСТКОВО")):
                    х["повторних_відкриттів"] += 1
                    події.append({
                        "номер": н, "sha": ша, "дата": дата, "коміт": назва,
                        "до": попередній, "після": ст,
                    })
    for л in текст.splitlines():
        if л.startswith("@@") and "\t" in л:
            зберегти()
            ша, дата, назва = л[2:].split("\t", 2)
            додані, видалені = {}, {}
        elif л.startswith(("+|", "-|")) and НОМЕР.match(л[1:]):
            р = читати(л[1:])[0]
            (додані if л[0] == "+" else видалені)[р["номер"]] = р
    зберегти()
    return відомі, події


def tsv(шлях, рядки, поля):
    with шлях.open("w", encoding="utf-8", newline="") as ф:
        п = csv.DictWriter(ф, fieldnames=поля, delimiter="\t", extrasaction="ignore")
        п.writeheader()
        п.writerows(рядки)


def мітка(р, ім):
    # У старих рядках мітки можуть стояти в різних клітинках.
    збіги = re.findall(rf"{ім}\s*:\s*([^;|]+)", р["повний"], re.I)
    return збіги[-1].strip().rstrip(" .*") if збіги else ""


def виконати(арг):
    дані = json.loads((ТЕКА / "розмітка.json").read_text())
    текст = git("show", f"{арг.база}:{ДОШКА}")
    рядки = читати(текст)
    індекс = {р["номер"]: р for р in рядки}
    ручні = {}
    for код, к in дані["корені"].items():
        for н in к["рядки"]:
            assert н in індекс, f"Невідомий рядок {н}"
            assert н not in ручні, f"Дві первинні причини рядка {н}"
            ручні[н] = код
    без = {int(н): п for н, п in дані["без_кореня"].items()}
    assert not (без.keys() & ручні.keys())
    походження, повтори = історія(арг.база)
    out = арг.вихід.resolve()
    if out == (КОРІНЬ / "аудит/дошка") or (КОРІНЬ / "аудит/дошка") in out.parents:
        raise ValueError("У каталог CI аудит/дошка/ писати не можна")
    out.mkdir(parents=True, exist_ok=True)
    for р in рядки:
        н = р["номер"]
        р["стан_аналізу"] = стан(р, дані["стани"])
        р["активний"] = р["стан_аналізу"] in {"відкрито", "частково", "приймання"}
        if н in ручні:
            р["корінь"] = ручні[н]
            р["метод"] = "ручний_перший"
            р["підстава"] = дані["корені"][ручні[н]]["механізм"]
        elif н in без:
            р["корінь"], р["метод"], р["підстава"] = "БЕЗ", "ручний_перший", без[н]
        else:
            р["корінь"], р["підстава"] = евристика(р, дані["корені"])
            р["метод"] = "евристика_історії"
        if р["активний"]:
            assert р["метод"] == "ручний_перший", f"Не розібрано активний {н}"
        р["виявлено"] = мітка(р, "виявлено")
        р["внесено"] = мітка(р, "внесено")
        р.update({к: v for к, v in походження.get(н, {}).items() if к != "номер"})
    активні = [р for р in рядки if р["активний"]]
    відкриті = [р for р in рядки if чисто(р["стан"]).startswith("ВІДКРИТО")]
    покриті = [р for р in активні if р["корінь"] != "БЕЗ"]
    зведення = {
        "база": git("rev-parse", арг.база).strip(),
        "дошка_sha256": hashlib.sha256(текст.encode()).hexdigest(),
        "рядків": len(рядки),
        "стани": dict(Counter(р["стан_аналізу"] for р in рядки)),
        "клітинок": dict(Counter(р["клітинок"] for р in рядки)),
        "без_слова_ЗАКРИТО_у_цілому_рядку": sum("ЗАКРИТО" not in р["повний"] for р in рядки),
        "явно_відкритих": len(відкриті),
        "явно_відкритих_із_коренем": sum(р["корінь"] != "БЕЗ" for р in відкриті),
        "активних": len(активні), "активних_із_коренем": len(покриті),
        "покриття_активних": round(100 * len(покриті) / len(активні), 2),
        "мітка_виявлено": sum(bool(р["виявлено"]) for р in рядки),
        "мітка_внесено": sum(bool(р["внесено"]) for р in рядки),
        "виявлено": dict(Counter(р["виявлено"] or "немає" for р in рядки)),
        "внесено": dict(Counter(р["внесено"] or "немає" for р in рядки)),
        "повторних_відкриттів_подій": len(повтори),
        "повторних_відкриттів_номерів": len({р["номер"] for р in повтори}),
    }
    групи = []
    for код, к in дані["корені"].items():
        група = [р for р in активні if р["корінь"] == код]
        прямі = set(к.get("прямі", []))
        assert прямі <= {р["номер"] for р in група}, f"Хибне пряме закриття {код}"
        групи.append({
            "корінь": код, "назва": к["назва"], "активних": len(група),
            "пряме_закриття_оцінка": len(прямі),
            "після_залежностей": len(група) - len(прямі),
            "явно_відкритих": sum(чисто(р["стан"]).startswith("ВІДКРИТО") for р in група),
            "номери": ", ".join(str(р["номер"]) for р in група),
            "прямі": ", ".join(map(str, sorted(прямі))),
            "історичних_евристично": sum(
                р["корінь"] == код and not р["активний"] for р in рядки
            ),
        })
    групи.sort(key=lambda р: (-р["пряме_закриття_оцінка"], -р["активних"], р["корінь"]))
    поля = [
        "номер", "лінія", "стан_аналізу", "активний", "корінь", "метод", "підстава",
        "вага", "джерело", "стан", "доказ", "клітинок", "виявлено", "внесено",
        "поява_sha", "поява_дата", "поява_коміт", "перше_закриття_sha",
        "повторних_відкриттів", "змін_стану",
    ]
    tsv(out / "усі_рядки.tsv", рядки, поля)
    tsv(out / "активні.tsv", активні, поля)
    реєстр = [{
        **{к: р.get(к, "") for к in [
            "номер", "лінія", "стан_аналізу", "активний", "корінь", "метод",
            "поява_sha", "поява_дата", "перше_закриття_sha",
        ]},
        "прямий_кандидат": р["номер"] in дані["корені"].get(р["корінь"], {}).get("прямі", []),
        "sha256_рядка": hashlib.sha256(р["повний"].encode()).hexdigest(),
        "короткий_доказ": р["доказ"][:180],
    } for р in рядки]
    tsv(out / "реєстр.tsv", реєстр, list(реєстр[0]))
    tsv(out / "корені.tsv", групи, list(групи[0]))
    tsv(out / "повторні_відкриття.tsv", повтори,
        ["номер", "sha", "дата", "коміт", "до", "після"])
    tsv(out / "без_кореня.tsv", [р for р in активні if р["корінь"] == "БЕЗ"], поля)
    tsv(out / "неоднорідний_формат.tsv", [р for р in рядки if р["клітинок"] != 7], поля)
    вибірка = random.Random(20261020).sample(sorted(відкриті, key=lambda р: р["номер"]), 30)
    tsv(out / "вибірка_30_без_міток.tsv", вибірка, ["номер", "джерело", "стан", "доказ"])
    другий = ТЕКА / "другий_прохід.json"
    if другий.exists():
        відповіді = json.loads(другий.read_text())
        перший = json.loads((ТЕКА / "перший_прохід.json").read_text())
        assert set(відповіді) == {str(р["номер"]) for р in вибірка}
        звірка = [{
            "номер": р["номер"], "перший": перший[str(р["номер"])],
            "другий": відповіді[str(р["номер"])]["корінь"],
            "збіг": перший[str(р["номер"])] == відповіді[str(р["номер"])]["корінь"],
            "остаточний": р["корінь"],
            "пояснення": відповіді[str(р["номер"])]["пояснення"],
        } for р in вибірка]
        tsv(out / "звірка_30.tsv", звірка, list(звірка[0]))
        зведення["другий_прохід"] = {
            "сі́д": 20261020, "випадків": 30,
            "збігів": sum(р["збіг"] for р in звірка),
            "відсоток": round(100 * sum(р["збіг"] for р in звірка) / 30, 2),
        }
    (out / "зведення.json").write_text(json.dumps(зведення, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({к: v for к, v in зведення.items() if к not in {"виявлено", "внесено"}}, ensure_ascii=False, indent=2))
    print("Результати:", out)


if __name__ == "__main__":
    п = argparse.ArgumentParser(description=__doc__)
    п.add_argument("--база", default=БАЗА)
    п.add_argument("--вихід", type=Path, default=Path("/tmp/д1"))
    виконати(п.parse_args())
