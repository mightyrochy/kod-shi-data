    ж, с = після_завершення()
    файл = Path(ж) / f"проходи/{ДОМЕН}/json_стан.json"
    стан = json.loads(файл.read_text(encoding="utf-8"))
    стан.pop("журнал_sha256")
    файл.write_text(json.dumps(стан, ensure_ascii=False), encoding="utf-8")
    for ф in (Path(ж) / f"проходи/{ДОМЕН}/json_сторінки").glob("*.json"):
        ф.unlink()
    п("5c старий маркер без суми, кешу нема", dict(http=[1, 2, 3], карток=3, завершено=True, сума_збігається=True), запуск(ж, с, range(1, 4)))

    # 6a. Два запуски поспіль після завершення (повний прохід кожен раз)
    ж, с = після_завершення()
    п("6a1 запуск після завершення з новим товаром", dict(http=[1, 2, 3], карток=4), запуск(ж, с, range(1, 5)))
    п("6a2 повторний запуск одразу після нього", dict(карток=4, завершено=True, сума_збігається=True), запуск(ж, с, range(1, 5)))

