"""Власна проба перевірки-2069-2: JSON-жнива Woo/Shopify після завершеного проходу й цілісність журналу.

Запуск: python власна_проба.py <корінь дерева з zhnyvarka/> [сімейство ...]
Не використовує вимір.py виконавця: сервер із пагінацією по 2 товари, власні сценарії й підрахунок.
HTTP — підроблений на рівні контексту браузера (request.get), тож справжній `_get` виконується.
"""
import asyncio, hashlib, json, sys, tempfile
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import patch

КОРІНЬ = Path(sys.argv[1]).resolve()
sys.path.insert(0, str(КОРІНЬ / "zhnyvarka"))
import виконавець  # noqa: E402
from json_прохід import прочитати_стан  # noqa: E402
from журнал_карток import прочитати  # noqa: E402

ДОМЕН = "json.test"
РОЗМІР = 2


class Відповідь:
    def __init__(self, код, тіло):
        self.status, self._т = код, тіло

    async def text(self):
        return self._т


class Запити:
    def __init__(self, сервер):
        self.с = сервер

    async def get(self, url, **_):
        n = int(url.rsplit("=", 1)[1])
        self.с.запити.append(n)
        if self.с.збій_на == n:
            return Відповідь(500, "err")
        ід = self.с.товари[(n - 1) * РОЗМІР:n * РОЗМІР]
        речі = [dict(id=i, handle=f"p{i}", permalink=f"https://json.test/p{i}", name="Чорна сукня",
                     title="Чорна сукня", images=[dict(src="https://json.test/photo.jpg")],
                     variants=[dict(option1="M", available=True)],
                     attributes=[dict(name="Розмір", terms=[dict(name="M")])]) for i in ід]
        return Відповідь(200, json.dumps({"products": речі} if self.с.сім == "shopify" else речі))


class Сервер:
    def __init__(self, сім):
        self.сім, self.товари, self.запити, self.збій_на = сім, [], [], None


class Контекст:
    def __init__(self, сервер):
        self.request = Запити(сервер)

    async def close(self):
        pass


class Браузер:
    def __init__(self, сервер):
        self.с = сервер

    async def new_context(self, **_):
        return Контекст(self.с)


def рецепт(сім, пошук=None):
    return dict(домен=ДОМЕН, сімейство=сім, транспорт="http", старт="https://json.test",
                пошук=пошук or ("/products.json?page={n}" if сім == "shopify" else "/wp-json/wc/store/products?page={n}"))


def запуск(ж, сервер, товари, стеля=300, збій=None, обрив_після=None, оновити=False, пошук=None):
    """Один запуск `_магазин` без мережі; повертає факти за журналом, а не за рядком зведення."""
    сервер.товари, сервер.запити, сервер.збій_на = list(товари), [], збій
    а = SimpleNamespace(журнал=ж, стеля=стеля, секунд_на_магазин=30, без_огляду=True, оновити_перелік=оновити)
    з = виконавець.Виконавець(а)
    оригінал = виконавець.Виконавець._пиши
    лічба = [0]

    def пиши(self, ш, зап):
        if обрив_після is not None and лічба[0] >= обрив_після:
            raise SystemExit("обрив")
        лічба[0] += 1
        return оригінал(self, ш, зап)
    вийняток = ""
    with patch.object(виконавець.Виконавець, "_пиши", пиши):
        try:
            asyncio.run(з._магазин(Браузер(сервер), рецепт(сервер.сім, пошук), asyncio.Semaphore(1)))
        except SystemExit:
            вийняток = "обрив"
    return факти(ж, сервер, вийняток)


def факти(ж, сервер, примітка=""):
    файл = Path(ж) / f"сирі/{ДОМЕН}.jsonl"
    записи = прочитати(файл)[0] if файл.is_file() else []
    унікальні = {з["url"] for з in записи}
    стан = прочитати_стан(ж, ДОМЕН)
    сума = hashlib.sha256(файл.read_bytes() if файл.is_file() else b"").hexdigest()
    кеш = sorted(int(п.stem) for п in (Path(ж) / f"проходи/{ДОМЕН}/json_сторінки").glob("*.json"))
    return dict(http=list(сервер.запити), карток=len(унікальні), рядків=len(записи),
                завершено=стан.get("завершено"), сторінка=стан.get("сторінка"),
                сума_збігається=стан.get("журнал_sha256") == сума, кеш=кеш, примітка=примітка)


def рядки_файлу(ж):
    return (Path(ж) / f"сирі/{ДОМЕН}.jsonl").read_bytes().splitlines(keepends=True)


def показати(сім, назва, очікування, ф):
    """Друкує факт і порівняння з очікуванням: очікування — {поле: значення}."""
    розбіжності = {к: (в, ф[к]) for к, в in очікування.items() if ф[к] != в}
    print(f"{сім}/{назва}: {json.dumps(ф, ensure_ascii=False)} | {'ОК' if not розбіжності else 'РОЗБІЖНІСТЬ ' + json.dumps(розбіжності, ensure_ascii=False)}")
    return not розбіжності


