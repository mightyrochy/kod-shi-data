    файл = Path(ж) / f"сирі/{ДОМЕН}.jsonl"
    дані = файл.read_bytes().rstrip(b"\n")
    ін = дані.rfind("Чорна".encode()) + 1  # посеред двобайтової літери
    файл.write_bytes(дані[:ін])
    п("3c хвіст обрізано посеред кирилиці", dict(http=[], карток=3, завершено=True, сума_збігається=True), запуск(ж, с, range(1, 4)))

    # 3d. Порушення й новий товар одночасно: відбудова без HTTP, новий — наступним запуском
    ж, с = після_завершення()
    файл = Path(ж) / f"сирі/{ДОМЕН}.jsonl"
    файл.write_bytes(рядки_файлу(ж)[0] + рядки_файлу(ж)[1][:20])
    п("3d1 пошкодження + новий товар: перший запуск", dict(карток=3, завершено=True, сума_збігається=True), запуск(ж, с, range(1, 5)))
    п("3d2 ... другий запуск знаходить новий", dict(http=[1, 2, 3], карток=4, завершено=True, сума_збігається=True), запуск(ж, с, range(1, 5)))

    # 3e. Обрізано на межі запису: останній цілий рядок прибрано
    ж, с = після_завершення()
    файл = Path(ж) / f"сирі/{ДОМЕН}.jsonl"
    файл.write_bytes(b"".join(рядки_файлу(ж)[:-1]))
    п("3e журнал обрізано на межі рядка", dict(http=[], карток=3, завершено=True, сума_збігається=True), запуск(ж, с, range(1, 4)))

    # 3f. Журнал очищено (порожній файл), крамниця без змін
    ж, с = після_завершення()
    (Path(ж) / f"сирі/{ДОМЕН}.jsonl").write_bytes(b"")
    п("3f журнал очищено до порожнього файлу", dict(http=[], карток=3, завершено=True, сума_збігається=True), запуск(ж, с, range(1, 4)))

    # 4a. Кеш сторінок є, журналу нема (позиція завершена)    ж, с = після_завершення()
    (Path(ж) / f"сирі/{ДОМЕН}.jsonl").unlink()
    п("4a кеш є, журналу нема (завершений прохід)", dict(http=[], карток=3, завершено=True, сума_збігається=True), запуск(ж, с, range(1, 4)))

    # 4b. Кеш є, журналу нема, прохід незавершений
