    # 4c. Журнал є, файл позиції зник, кеш лишився: чужий кеш не використовується
    ж, с = після_завершення()
    (Path(ж) / f"проходи/{ДОМЕН}/json_стан.json").unlink()
    п("4c позиції нема, кеш лишився", dict(http=[1, 2, 3], карток=3, завершено=True, сума_збігається=True), запуск(ж, с, range(1, 4)))

    # 4d. Позиція є, журнал і кеш видалено
    ж, с = після_завершення()
    (Path(ж) / f"сирі/{ДОМЕН}.jsonl").unlink()
    for ф in (Path(ж) / f"проходи/{ДОМЕН}/json_сторінки").glob("*.json"):
        ф.unlink()
    п("4d позиція є, журналу й кешу нема", dict(http=[1, 2, 3], карток=3, завершено=True, сума_збігається=True), запуск(ж, с, range(1, 4)))

    # 5a. Стара позиція: маркер кінця без суми, журнал цілий, кеш є, крамниця без змін
    ж, с = після_завершення()
    файл = Path(ж) / f"проходи/{ДОМЕН}/json_стан.json"
    стан = json.loads(файл.read_text(encoding="utf-8"))
    стан.pop("журнал_sha256")
