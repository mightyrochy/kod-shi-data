    # 3b. Пошкоджено байт посеред рядка 1 (невалідний UTF-8), решта цілі
    ж, с = після_завершення()
    рядки = рядки_файлу(ж)
    рядки[0] = рядки[0][:30] + b"\xff\xfe" + рядки[0][32:]
    (Path(ж) / f"сирі/{ДОМЕН}.jsonl").write_bytes(b"".join(рядки))
    п("3b пошкоджено байти посеред рядка 1", dict(http=[], карток=3, завершено=True, сума_збігається=True), запуск(ж, с, range(1, 4)))

