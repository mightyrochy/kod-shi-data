def вердикт(є):
    return "ВАДА Є" if є else "ВАДИ НЕМАЄ"


def а():
    """А: обірваний UTF-8 у JSONL чи зведенні — падіння обходу до запуску всіх крамниць."""
    for джерело in ("jsonl", "зведення", "jsonl-середина", "зведення-середина"):
        for обрізати in (1, 2):
            with tempfile.TemporaryDirectory(prefix="перевірка-2069-2-А-") as журнал:
                if джерело.startswith("jsonl"):
                    файл = Path(журнал) / "сирі/json.test.jsonl"
                    файл.parent.mkdir()
                    текст = '{"url":"https://json.test/p1","назва":"Сукня'
                else:
                    файл = Path(журнал) / "зведення_жнив.tsv"
                    текст = "\t".join(обхід.ШАПКА_ЗВЕДЕННЯ) + "\n2026-10-28\tjson.test\tСукня"
                дані = текст.encode("utf-8")[:-обрізати]
                if джерело.endswith("-середина"):  # обрив не в кінці: далі ще один цілий рядок
                    дані += b"\n" + (b'{"url":"https://json.test/p2"}\n' if джерело.startswith("jsonl") else b"")
                файл.write_bytes(дані)
                результат = []
                for спроба in (1, 2):
                    with patch.object(обхід, "запустити_крамниці", side_effect=lambda ком, крамниці, *межі: {д: (0, False) for д in крамниці}) as запуск:
                        try:
                            обхід.main(["--журнал", журнал, "--магазини", "json.test,ok.com", "--циклів", "1"])
                            результат.append("без падіння")
                        except UnicodeDecodeError:
                            результат.append(f"UnicodeDecodeError, запусків={запуск.call_count}")
                        except Exception as е:  # noqa
                            результат.append(f"{type(е).__name__}: {str(е)[:50]}")
                print(f"А/{джерело}/-обрізано {обрізати} Б: {результат} → {вердикт(any('Error' in р for р in результат))}")


def б():
    """Б: дописування до обірваного JSONL — нова картка непрочитна, маркер кінця фіксується."""
    for сімейство in ("woo", "shopify"):
        for хвіст in (b'{"url":', '{"url":"https://json.test/p0","назва":"Су'.encode() + "к".encode()[:1]):
            with tempfile.TemporaryDirectory(prefix="перевірка-2069-2-Б-") as журнал:
                файл = Path(журнал) / "сирі/json.test.jsonl"
                файл.parent.mkdir()
                файл.write_bytes(хвіст)
                стан, запитів = прогін(журнал, сімейство, [порція(сімейство, [РІЧ]), порція(сімейство, [])])
                підсумок = dict(обхід.результати(журнал, "json.test"))
                Path(журнал, "обхід_стан.tsv").unlink()
                стан2, запитів2 = прогін(журнал, сімейство, [])
