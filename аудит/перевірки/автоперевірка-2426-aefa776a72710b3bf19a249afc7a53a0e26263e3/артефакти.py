"""Перевіряє дублікати переданої вибірки та відбитків входу без доступу до історій."""
from collections import defaultdict
from pathlib import Path
import re
import sys


def головна():
    """Друкує лише факти, видимі в закомічених артефактах голови."""
    корінь = Path(sys.argv[1]) / "аудит/корені"
    витяг = (корінь / "ПК-дотримання-правил-вибірка-витяг.md").read_text(encoding="utf-8")
    дії = re.findall(r"^## (\d+)\. (.+?) · (.+?) · (.+?) · (.+?) · `([^`]+)`$", витяг, re.M)
    ідентифікатори = defaultdict(list)
    for номер, час, роль, сесія, інструмент, ід in дії:
        ідентифікатори[ід].append(f"{номер}:{роль}:{сесія}")
    print(f"рядків вибірки: {len(дії)}; різних tool_use.id: {len(ідентифікатори)}")
    for ід, місця in ідентифікатори.items():
        if len(місця) > 1:
            print(f"дублікат {ід}: {'; '.join(місця)}")
    відбитки = defaultdict(list)
    вивід = (корінь / "ПК-дотримання-правил-вивід.txt").read_text(encoding="utf-8")
    for роль, сесія, кількість, хеш in re.findall(r"^# вхід (\S+) (\S+): подій (\d+), (\w+)$", вивід, re.M):
        відбитки[(кількість, хеш)].append(f"{роль}:{сесія}")
    for (кількість, хеш), місця in відбитки.items():
        if len(місця) > 1:
            print(f"однаковий відбиток {хеш}, подій {кількість}: {'; '.join(місця)}")
    for номер, розділ in enumerate(re.split(r"^## \d+\. ", витяг, flags=re.M)[1:], 1):
        for ша in re.findall(r'expectedHeadSha\\?":\\?"?\s*\\?"([0-9a-f]+)', розділ):
            print(f"вибірка {номер}: expectedHeadSha, знаків {len(ша)}")


if __name__ == "__main__":
    головна()
