"""Звіряє збережені виміри виходу в екран ДО та ПІСЛЯ."""
import json
from pathlib import Path


def main():
    тека = Path(__file__).parent
    до, після = [json.loads((тека / (ім + ".json")).read_text(encoding="utf8")) for ім in ("до", "після")]
    прийняті = [(а, б) for а, б in zip(до["повтор"], після["повтор"]) if а["стан"] == "translated"]
    факт = {"текстів": len(після["повтор"]), "прийнято": len(прийняті),
            "відхилено": sum(б["стан"] != "translated" for б in після["повтор"]),
            "загальні_написи": [sum(р["екран"] == "— без тексту" for р in в["повтор"]) for в in (до, після)],
            "прийняті_дослівні": all(а["текст"] == б["текст"] == а["екран"] == б["екран"] for а, б in прийняті),
            "стани_однакові": [р["стан"] for р in до["повтор"]] == [р["стан"] for р in після["повтор"]],
            "чиста_картка_однакова": до["чистаКартка"] == після["чистаКартка"],
            "її_слова_дослівні": all(р["вона"] == "My own words" for р in після["чат"]),
            "підказки_не_надсилають_шаблон": після["хибнаПідказка"]["надіслано"] == 0,
            "чиста_підказка": після["чистаПідказка"] == {"надіслано": 1, "поле": "ввечері"},
            "фото_однакові": до["браузер"]["фото"] == після["браузер"]["фото"],
            "фото_завантажені": all(р["ширина"] > 0 for р in після["браузер"]["фото"]),
            "переповнення": після["браузер"]["переповнення"], "помилки": після["помилки"]}
    assert all(факт[к] for к in ("прийняті_дослівні", "стани_однакові", "чиста_картка_однакова",
                                "її_слова_дослівні", "підказки_не_надсилають_шаблон", "чиста_підказка",
                                "фото_однакові", "фото_завантажені"))
    assert факт["текстів"] == len(до["повтор"]) and факт["загальні_написи"][1] == 0
    assert not факт["переповнення"] and not факт["помилки"]
    текст = json.dumps(факт, ensure_ascii=False, indent=2)
    (тека / "порівняння.json").write_text(текст + "\n", encoding="utf8")
    print(текст)


if __name__ == "__main__":
    main()
