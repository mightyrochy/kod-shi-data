/* Виконує справжню стадію вибору з детермінованими відповідями, без моделі. */
const fs = require('fs'), vm = require('vm'), path = require('path');
const дані = JSON.parse(fs.readFileSync(process.argv[3], 'utf8'));
const контекст = {ЗБ: {діагноз: []}, СТАДІЯ_П: {}, малюватиТокениП() {}, текстомАбоКодамиП: String};
vm.createContext(контекст);
vm.runInContext(fs.readFileSync(path.join(process.argv[2], 'показ', 'збирання_руки.js'), 'utf8')
  + '\nglobalThis.перевірити = стадіяВибору;', контекст);
const запити = [];
const к = {рука: '1', вх: {}, донор: false, лічильники: {викликів: 0}, свідоміЗІд: [],
  мітка() {}, станОбриву() {return {};}, зОбривом(_, вхід) {return вхід;},
  async модельПРуки(промпт) {
    if (промпт === 'ВИБІР') return дані.текст_вибору;
    запити.push(JSON.parse(промпт));
    return '{}';
  },
  async відМоделіРуки(вхід) {
    if (вхід.відповідь === 'ВИБІР_V1') return {вибір: дані.вибір};
    return {повнота: {ід: [], повний: false}, промпт_повноти: null};
  }};
контекст.перевірити(к, {текст: '', в: дані.в, ітерацій: 2, збій: false})
  .then(() => {console.log(JSON.stringify({названо: дані.вибір.названо,
    ремонтується: запити.map(п => п.образи.map(о => о.ід)), діагноз: контекст.ЗБ.діагноз}, null, 2));
    process.exitCode = Number(!запити.length || запити.some(п => !п.образи.some(о => о.ід === дані.вибір.названо)));})
  .catch(помилка => {console.error(помилка); process.exitCode = 1;});
