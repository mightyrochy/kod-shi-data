"""Міряє залежність ремонту від порядку складу за незмінних оцінок судді."""
import json
import pathlib
import random
import sys

sys.path.insert(0, sys.argv[1])
import повнота_образу as П

слоти = ['верх', 'низ', 'взуття', 'сумка', 'верхній_шар', 'шарф', 'головний_убір', 'пояс', 'прикраса']
основа = [f'z{i}' for i in range(len(слоти))]
кандидати = {с: [dict(id=f'a{i}{j}', слот=с) for j in range(6)] for i, с in enumerate(слоти)}
словник = {r['id']: r for пул in кандидати.values() for r in пул}
словник.update({і: dict(id=і, слот=с) for і, с in zip(основа, слоти)})


def суд(склади):
    """Лише a05 прибирає гейт; зняття лишає структурну діру. Це фікстура, без моделі."""
    return [dict(ід='о1', речі=склад, структура=dict(ок=len(склад) == 9,
                 блокери=[] if len(склад) == 9 else [dict(код='неповний')]),
                 знахідки=[] if 'a05' in склад
                 else [dict(правило='K-KOH-05', регістр='гейт', речі=[])]) for склад in склади]


факти = []
for сід in range(30):
    склад = list(основа)
    random.Random(сід).shuffle(склад)
    вирок = dict(ід='о1', речі=склад, структура=dict(ок=True, блокери=[]),
                 знахідки=[dict(правило='K-KOH-05', регістр='гейт', речі=[])])
    додатково = dict(бюджет=dict(речей=1000000)) if '--без-стелі' in sys.argv else {}
    ід, зміни, звіт = П._ремонт_гейтів(склад, {}, вирок, кандидати, словник, {}, суд, **додатково)
    картка = (П.повнота_набору(dict(образи=[вирок]), кандидати=кандидати,
              каталог=[словник[і] for і in основа], суддя=суд) if not додатково else None)
    факти.append(dict(сід=сід, склад=sorted(ід or []), зміна=зміни,
                      картка_повна=картка.get('повний') if картка else None,
                      варіантів=звіт['варіантів'], відкинуто=звіт.get('відкинуто_варіантів', 0)))
print(json.dumps(dict(перестановок=30, відмінних=sum(x['склад'] != факти[0]['склад'] for x in факти),
                      без_ремонту=sum(not x['склад'] for x in факти),
                      факти=факти), ensure_ascii=False, indent=2))
