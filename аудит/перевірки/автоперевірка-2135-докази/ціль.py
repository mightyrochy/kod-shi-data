"""Готує дані справжнього вибору й ремонту для проби стадії показу."""
import json
import pathlib
import sys
sys.path.insert(0, sys.argv[1])
import повнота_образу as П

кандидати = {'верх': [dict(id=і, слот='верх') for і in 'abc']}
образи = [dict(ід='о1', речі=['a', 'b'], структура=dict(ок=False,
               блокери=[dict(код='слот_двічі')])),
          dict(ід='о2', речі=['a', 'b', 'c'], структура=dict(ок=False,
               блокери=[dict(код='слот_двічі'), dict(код='слот_двічі')]))]
вердикт = dict(образи=образи)
текст = json.dumps(dict(версія='1', обрано='о2', прибрати=[]), ensure_ascii=False)
вибір = П.вибір_з_json(текст, вердикт, кандидати=кандидати)
повнота = П.повнота_набору(вердикт, кандидати=кандидати)
ремонт = (П.вердикт_повноти(вердикт) if '--до' in sys.argv
          else П.вердикт_повноти(вердикт, обрано=повнота['образ']))
дані = dict(текст_вибору=текст, вибір=вибір, в=dict(образи=[{}, {}], вердикт=вердикт,
            вибір_над=вердикт, повнота=повнота, промпт_лише_вибору='ВИБІР',
            промпт_повноти=json.dumps(ремонт, ensure_ascii=False)))
pathlib.Path(sys.argv[2]).write_text(json.dumps(дані, ensure_ascii=False, indent=2), encoding='utf-8')
print(json.dumps(dict(названо=вибір['названо'], прийнятих_речей=len(вибір['ід']),
                     ціль_коду=повнота['образ'], ремонт=[о['ід'] for о in ремонт['образи']]), ensure_ascii=False))
