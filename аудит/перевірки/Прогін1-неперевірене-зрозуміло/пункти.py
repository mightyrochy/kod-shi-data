"""Вимір: пункти «неперевіреного» картки з моста (від_моделі) на синтетичних образах із пулу, офлайн."""
import sys, os, json, collections
Д = os.path.abspath(sys.argv[1]); sys.path.insert(0, Д); os.chdir(Д)
import bridge as B, feed as _Ф
КАТ = _Ф.каталог_на_диску("каталог_повний.xml")
ПАСП = {"подія": "день", "формат": "вулиця", "тривалість_год": 9, "рух": "ходити", "дрес_код": "smart_casual", "ошатність": [3, 6]}
СЦЕН = {
 "мороз_ожеледь_офіс": dict(нагода="робота", місце="офіс", година=9, смуга_погоди="cold", опади="сніг", ожеледиця="так"),
 "ресторан_вечір_зима": dict(нагода="побачення", місце="ресторан", година=19, смуга_погоди="cold"),
 "дощ_робота": dict(нагода="робота", місце="офіс", година=9, смуга_погоди="mild", опади="дощ"),
 "весілля_літо": dict(нагода="весілля", місце="ресторан", година=16, смуга_погоди="hot"),
}
вих = {}
for ім, сц in СЦЕН.items():
    вх = json.load(open("стенд_вх.json")); вх["сценарій"] = сц; вх["каталог"] = КАТ
    п = json.loads(B.виклик("паспорт", json.dumps(dict(json_моделі=json.dumps(ПАСП), сценарій=сц, вимоги=""), ensure_ascii=False)))
    вх["паспорт"] = п["паспорт"]
    з = json.loads(B.виклик("запити", json.dumps(dict(вх, пакети=1), ensure_ascii=False)))
    пул = ((з.get("пакети") or {}).get("1") or {}).get("пул") or {}
    образи = []
    for і in range(4):
        н = [рч[і % len(рч)]["н"] for сл, рч in sorted(пул.items()) if рч][:7]
        образи.append(dict(ід="о%d" % (і + 1), підпис="проба", речі=н, свідомо=[]))
    вм = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=json.dumps(dict(версія="1", образи=образи), ensure_ascii=False)), ensure_ascii=False)))
    вих[ім] = вм
json.dump(вих, open(sys.argv[2], "w"), ensure_ascii=False)
for ім, вм in вих.items():
    print(ім, sorted(вм.keys())[:60])
