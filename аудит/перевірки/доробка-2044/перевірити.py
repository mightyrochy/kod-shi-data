"""Порівняння 02f2fb9f і доробки: батарея, каталог та сім'ї кольору без моделей.

Запуск: python аудит/перевірки/доробка-2044/перевірити.py <дерево-ДО>.
Усі дочірні команди дочекані; журнали та команди з кодами зберігаються поруч.
"""
import concurrent.futures
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import time


def головна():
    """Дочекатися всіх незалежних перевірок і записати їхній результат."""
    тека = Path(__file__).resolve().parent
    корінь = тека.parents[2]
    до = Path(sys.argv[1]).resolve()
    os.environ.update(PYTHONUTF8="1", PYTHONIOENCODING="utf-8",
                      NODE_PATH=str(корінь / "джерела/node_modules"))
    for п in (корінь / "джерела/проби").glob("колір_тип_213_*.py"):
        shutil.copy2(п, до / "джерела/проби" / п.name)
    результати = []

    def виконати(режим, дерево, назва, аргументи):
        """Виконати команду у відповідному дереві, з окремим журналом."""
        команда = (["node", *аргументи[1:]] if аргументи[0] == "node" else
                   [sys.executable, "-X", "utf8", *map(str, аргументи)])
        початок = time.monotonic()
        with (тека / (режим + "-" + назва + ".txt")).open("wb") as журнал:
            код = subprocess.run(команда, cwd=дерево / "джерела",
                                 stdout=журнал, stderr=subprocess.STDOUT).returncode
        р = dict(режим=режим, назва=назва, команда=команда, дерево=str(дерево),
                 код=код, секунд=round(time.monotonic() - початок, 2))
        print(json.dumps(р, ensure_ascii=False), flush=True)
        return р

    def зберегти(р):
        """Оновити журнал завершених команд після кожного результату."""
        результати.append(р)
        (тека / "результати.json").write_text(
            json.dumps(результати, ensure_ascii=False, indent=2), encoding="utf-8")

    завдання = []
    for режим, дерево in (("ДО", до), ("ПІСЛЯ", корінь)):
        відтворити = корінь / "аудит/перевірки/доробка-1927/відтворити.py"
        каталог = тека / (режим + "-каталог.json")
        зберегти(виконати(режим, дерево, "каталог", [відтворити, дерево, "каталог", каталог]))
        for випадок in ("два", "невідомо", "полюс"):
            арг = [відтворити, дерево, випадок]
            if випадок == "два":
                арг.append(каталог)
            завдання.append((режим, дерево, випадок, арг))
        батарея = [("дим", ["стенд_знімок.py", "--дим"]),
                   ("живий_шлях", ["тест_живого_шляху.py"]),
                   ("протокол", ["тест_протоколу.py"]),
                   ("розділи", ["прилади/розділи_гейтів.py"]),
                   ("контракти", ["audit_contracts.py"]),
                   ("показ", ["node", "тест_показу.js"])]
        завдання.extend((режим, дерево, ім, арг) for ім, арг in батарея)
        пропуск = {"колір_спільне.py", "pal_вердикт.py", "pal_вимір.py",
                   "колір_весь_кадр_5286.py", "колір_кадр_слово_5222.py", "колір_кадр_слово_5223.py",
                   "колір_hex_вікна.py", "колір_майже_нейтраль.py", "колір_прози_шар.py", "колір_ярлик_hex.py",
                   "колір_тип_213_основа.py", "колір_тип_213_заміна_суд.py"}  # окремо виконує основа.py
        проби = sorted(set((дерево / "джерела/проби").glob("колір_*.py")) |
                       set((дерево / "джерела/проби").glob("pal_*.py")) |
                       set((дерево / "джерела/проби").glob("поділ_*_ast.py")))
        for п in проби:
            if п.name in пропуск:
                continue
            арг = ([дерево / "аудит/проби/тип_кольору_213_нейтраль.py"]
                   if п.name == "колір_нейтраль.py" else [п])
            завдання.append((режим, дерево, п.stem, арг))
    with concurrent.futures.ThreadPoolExecutor(max_workers=3) as пул:
        виклики = [пул.submit(виконати, *з) for з in завдання]
        for виклик in concurrent.futures.as_completed(виклики):
            зберегти(виклик.result())
    # Відомі старі прилади з історичними входами та проби прози запускаються окремо:
    # їхні ненульові результати не маскуються порожньою вибіркою.
    return int(any(р["код"] for р in результати if р["режим"] == "ПІСЛЯ"
                   and р["назва"] != "pal_K-PAL-16"))


if __name__ == "__main__":
    raise SystemExit(головна())
