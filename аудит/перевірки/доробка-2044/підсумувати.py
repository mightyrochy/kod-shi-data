"""Звірити повноту завершених команд і скласти компактний підсумок доказів."""
import json
from pathlib import Path
import subprocess


def головна():
    """Відокремити очікувані ДО та давні червоні від нових відхилень ПІСЛЯ."""
    тека = Path(__file__).resolve().parent
    корінь = тека.parents[2]
    def читати(ім):
        """Прочитати записаний результат завершеної перевірки."""
        return json.loads((тека / ім).read_text(encoding="utf-8"))
    р = читати("результати.json")
    батарея = {"дим", "живий_шлях", "протокол", "розділи", "контракти", "показ"}
    випадки = {"колір_тип_213_метал", "колір_тип_213_заміна", "колір_тип_213_композитор",
               "колір_тип_213_контраст", "колір_тип_213_опора"}
    звіт, помилки = {}, []
    for режим in ("ДО", "ПІСЛЯ"):
        рядки = [х for х in р if х["режим"] == режим]
        за_ім = {х["назва"]: х for х in рядки}
        б = [х for х in рядки if х["назва"] in батарея]
        а = [х for х in рядки if х["назва"].startswith("поділ_") and х["назва"].endswith("_ast")]
        дозволені = {"pal_K-PAL-16"} | (випадки if режим == "ДО" else set())
        нові = [х["назва"] for х in рядки if х["код"] and х["назва"] not in дозволені]
        if len(б) != 6 or any(х["код"] for х in б):
            помилки.append(режим + ": батарея не 6/6")
        if len(а) != 14 or any(х["код"] for х in а):
            помилки.append(режим + ": AST не 14/14")
        if not випадки <= за_ім.keys() or any(за_ім[ім]["код"] != (1 if режим == "ДО" else 0)
                                              for ім in випадки if ім in за_ім):
            помилки.append(режим + ": неповне або неочікуване ДО/ПІСЛЯ власних проб")
        помилки.extend(режим + ": " + ім for ім in нові)
        звіт[режим] = dict(команд=len(рядки), батарея_пройшла=sum(х["код"] == 0 for х in б),
                           AST_пройшли=sum(х["код"] == 0 for х in а),
                           ненульові=[х["назва"] for х in рядки if х["код"]],
                           нові_відхилення=нові)
    набори = [{х["назва"] for х in р if х["режим"] == режим} for режим in ("ДО", "ПІСЛЯ")]
    if набори[0] != набори[1]:
        помилки.append("Набори команд ДО й ПІСЛЯ різні")
    дод = читати("додаткові-результати.json")
    if len(дод) != 14 or any(х["код"] for х in дод if х["назва"] not in {"колір_прози_шар", "колір_ярлик_hex"}):
        помилки.append("Неочікуваний результат історичних проб")
    осн = читати("основа-результати.json")
    if [х["код"] for х in осн] != [1, 0]:
        помилки.append("Основа: не підтверджено ДО=1, ПІСЛЯ=0")
    зам = читати("заміна-суд-результати.json")
    if [х["код"] for х in зам] != [1, 0]:
        помилки.append("Заміна зі штатним судом: не підтверджено ДО=1, ПІСЛЯ=0")
    ст = читати("стенд-відмінності.json")
    if not ст["id_тотожні"] or ст["відмінності"] or ст["сцен"] != 6:
        помилки.append("Стенд: id або результати різняться")
    if not читати("каталог-порівняння.json")["тотожні"]:
        помилки.append("Каталоги різняться")
    код = subprocess.run(["git", "diff", "--quiet", "6c3fcae6ceb2cfa4b97bb76613acdbcdc156a150", "--", "джерела"],
                        cwd=корінь).returncode
    if код:
        помилки.append("Код відрізняється від зафіксованого ПІСЛЯ")
    звіт.update(додаткових_команд=len(дод), основа_ДО_ПІСЛЯ=[х["код"] for х in осн],
                 заміна_суд_ДО_ПІСЛЯ=[х["код"] for х in зам],
                 стенд_сцен=ст["сцен"], стенд_відмінностей=len(ст["відмінності"]), помилки=помилки)
    (тека / "підсумок.json").write_bytes(json.dumps(звіт, ensure_ascii=False, indent=2).encode("utf-8"))
    print(json.dumps(звіт, ensure_ascii=False, indent=2))
    return int(bool(помилки))


if __name__ == "__main__":
    raise SystemExit(головна())
