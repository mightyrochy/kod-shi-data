"""Порівнює валідацію дошки з фрагментом звіту й без нього, нічого не згортає."""
import json
from pathlib import Path
import sys

репо = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(репо / 'джерела/прилади'))
import згорнути_дошку as м

назва = Path(__file__).parent.name
фрагмент = str(репо / ('аудит/дошка/gemini/' + назва + '.md'))
зібрати = м.зібрати_файли
з_фрагментом, помилки_з = м.згорнути(лише_перевірити=True)
м.зібрати_файли = lambda: [ш for ш in зібрати() if Path(ш).resolve() != Path(фрагмент).resolve()]
без_фрагмента, помилки_без = м.згорнути(лише_перевірити=True)
звіт = dict(з_фрагментом=з_фрагментом, без_фрагмента=без_фрагмента,
            помилки_з=помилки_з, помилки_без=помилки_без, нових_помилок=sorted(set(помилки_з)-set(помилки_без)))
print(json.dumps(звіт, ensure_ascii=False, indent=2))
raise SystemExit(bool(звіт['нових_помилок']))
