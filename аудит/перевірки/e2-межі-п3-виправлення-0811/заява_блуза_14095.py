import json, os, sys
sys.path.insert(0, os.path.join(os.getcwd(), "джерела"))
import мовний_шар as М
Т = "аудит/проби/Е1-нічний-живий-20261107/ж1_робота_блуза_фото/VIDPOVIDI/"
def відповідь(ф):
    т = open(Т + ф, encoding="utf-8").read()
    return т.split("── ВІДПОВІДЬ", 1)[1].split("──\n", 1)[1].strip()
перша, друга = відповідь("seed3_01_мовний_шар_хід_розмови.txt"), відповідь("seed3_02_мовний_шар_хід_розмови.txt")
р = json.loads(М.мова({"розмова": {"нове": "блуза"}, "відповідь_моделі": друга, "перша_відповідь": перша}))
print("незнайомі:", р.get("незнайомі"))
print("не_взято:", р.get("не_взято"))
print("не_записано прочитаного:", р.get("не_записано"), "· причина:", р.get("причина"))
пш = М.паспорт_з_шару(р.get("внутрішня") or {}, {}, частини=р.get("частини") or {}, не_взято=р.get("не_взято"),
                      не_записано_ходу=р.get("не_записано"), слова_ходу=["Мені на роботу, хочу блузу"])
print("не_записано репліки (not_recorded):", пш.get("не_записано"), "· мовець:", пш.get("мовець"))
