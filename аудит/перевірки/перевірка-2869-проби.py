"""Незалежні відтворення зауважень PR 2869; реалізацію не змінює.

Запуск: python аудит/перевірки/перевірка-2869-проби.py <дерево голови PR>.
Нульовий код означає, що описані у звіті факти відтворилися.
"""
import json
from pathlib import Path
import sys
import tempfile

sys.stdout.reconfigure(encoding='utf-8')
голова = Path(sys.argv[1]).resolve()
sys.path.insert(0, str(голова / 'джерела/прилади'))
from е2_обробники import граф
from корінь_е2_усе_з_розмови import вимір


def проба(назва, код, очікувано):
    """Міряє мінімальне дерево незміненим приладом голови."""
    with tempfile.TemporaryDirectory(prefix='перевірка-2869-') as тека:
        дж = Path(тека) / 'джерела'
        дж.mkdir()
        (дж / 'дія.js').write_text(код, encoding='utf-8')
        р = вимір(граф(тека))
    підсумок = dict(місць=len(р['місця']), функцій=len(р['функції']),
                   невідомих=р['невідомих'])
    print(назва + ': ' + json.dumps(підсумок, ensure_ascii=False))
    assert підсумок == очікувано, (назва, підсумок, очікувано)


