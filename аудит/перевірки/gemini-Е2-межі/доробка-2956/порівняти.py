"""Звірити промпти, форму поля й усі результати повтору до та після доробки."""
import json
from pathlib import Path


def main():
    """Виконати вимір лише під час запуску скрипту."""
    ТЕКА = Path(__file__).resolve().parent
    до, після = (json.loads((ТЕКА / (назва + ".txt")).read_text(encoding="utf-8"))
                  for назва in ("вимір-до", "вимір-після"))
    assert до["розмова"] == після["розмова"]
    assert після["розмова"]["правил_підвидів"] == 1
    assert до["повтор"] == після["повтор"]
    форма = dict(після["схема_місця"])
    назва = форма.pop("title")
    assert форма == до["схема_місця"]
    assert назва in після["репліка"]
    assert "office_corporate" not in після["репліка"]
    assert "office_creative" not in після["репліка"]
    assert len(після["репліка"]) < len(до["репліка"])
    print(json.dumps({"розмова_тотожна": True, "форма_без_title_тотожна": True,
                      "повтор_тотожний": True, "лічби_повтору": після["повтор"]["лічба"],
                      "репліка_до": len(до["репліка"]), "репліка_після": len(після["репліка"])},
                     ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
