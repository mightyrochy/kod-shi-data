"""ДО/ПІСЛЯ на тому самому корпусі: модулі бази відновлюються лише в TEMP задачі."""
import json
import os
from pathlib import Path
import subprocess
import sys
import tarfile

ТЕКА = Path(__file__).resolve().parent
РЕПО = ТЕКА.parents[3]
ДЖЕРЕЛА = РЕПО / 'джерела'
БАЗА = '519b052fb1bee0fe0c9d0cd196e7b08351d49b68'


def вимір(код):
    """Прогнати записані ходи й однакові входи через задані модулі продукту."""
    sys.path[:0] = [str(код), str(ДЖЕРЕЛА / 'прилади'), str(ДЖЕРЕЛА)]
    import replay_картки as З
    import мовний_шар as М, картка_запиту as К, паспорт_нагоди as Н
    import розбір_відповідей as В, руки_без_коду as Р, оцінка_образу as О
    import дріт_моделі as Д, пакет_моделі as П
    п = {}
    К.записати(п, 'місце', 'парк', 'her', 'парк')
    К.записати(п, 'нагода', 'побачення', 'her', 'йду на зустріч')
    К.записати(п, 'темп_c', 18, 'default')
    текст = 'Синя сукня, прямий крій, міді, синій #334488, бавовна'
    речі = В.речі_з_тексту(текст)['речі']
    спорт = М.паспорт_з_шару({'occasion': 'sport', 'quotes': {'occasion': 'йога зранку'}}, {},
                           слова_ходу=['йога зранку'])['паспорт']
    результат = dict(
        лічба=З.виміряти(ДЖЕРЕЛА / 'проби/дані/картка_запиту.json', код)['лічба'],
        плитки=М.плитки_кодами({}, п),
        макіяж=json.loads(Н.промпт_паспорта({'макіяж': {'губи': '#bb3344'}, 'типові_поля': []}, '')),
        основа=Р.головний_колір({'база': 'синій', 'база_за_замовчуванням': True}),
        питання=О._питання_дроту('Чи пасує?'),
        колір={к: речі[0].get(к) for к in ('джерело_кольору', 'колір_тип', 'колір_не_вимір', 'впевненість_джерело')},
        річ=Д.річ(П.річ_пулу(речі[0], {})),
        рух=спорт['картка_запиту'].get('рух'),
        реєстр=Д.вердикт({'реєстр': {'провідний': 'мінімалізм', 'поруч': []}}).get('register'),
    )
    print(json.dumps(результат, ensure_ascii=False, indent=2))


def головна():
    """Зберегти базу й обидва виміри, звірити незмінність показників повтору записів."""
    if len(sys.argv) > 1:
        вимір(Path(sys.argv[1]))
        return
    тека_бази = Path(os.environ['TEMP']) / 'е2-межі-база-модулів'
    тека_бази.mkdir(exist_ok=True)
    процес = subprocess.Popen(['git', 'archive', БАЗА, 'джерела'], cwd=РЕПО, stdout=subprocess.PIPE)
    with tarfile.open(fileobj=процес.stdout, mode='r|') as архів:
        for член in архів:
            частини = Path(член.name).parts
            if член.isfile() and len(частини) == 2:
                (тека_бази / частини[-1]).write_bytes(архів.extractfile(член).read())
    if процес.wait():
        raise RuntimeError('git archive не завершився успішно')
    дані = {}
    for назва, код in (('до', тека_бази), ('після', ДЖЕРЕЛА)):
        р = subprocess.run([sys.executable, '-X', 'utf8', __file__, str(код)], cwd=РЕПО,
                           capture_output=True, encoding='utf-8')
        if р.returncode:
            raise RuntimeError(р.stderr)
        (ТЕКА / f'дріт-{назва}.json').write_text(р.stdout, encoding='utf-8')
        дані[назва] = json.loads(р.stdout)
    assert дані['до']['лічба'] == дані['після']['лічба'], дані
    assert дані['до']['основа']['chosen_by'] == 'code_she_kept_it'
    assert дані['після']['основа']['chosen_by'] == 'code'
    assert дані['до']['колір']['джерело_кольору'] == 'фото'
    assert дані['після']['колір']['джерело_кольору'] == 'модель'
    assert дані['після']['річ']['color_not_measured']['source'] == 'model_hex'
    assert дані['після']['рух']['джерело'] == 'derived' and not дані['після']['рух']['уривок']
    assert дані['після']['реєстр']['source']['kind'] == 'derived'
    print('ДО → ПІСЛЯ: колір фото → модель, основа «вона лишила» → типове коду; вид плиток доходить до дроту.')
    print('58 записаних ходів: усі показники збігаються; годинна проба вже червона на базі.')


if __name__ == '__main__':
    головна()
