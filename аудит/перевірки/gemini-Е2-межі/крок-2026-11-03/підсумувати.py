"""Звести завершені журнали кроку; не підвищувати неповну батарею до зеленої."""


def main():
    """Виконати перевірку або запис стану лише при прямому запуску."""
    import json, re, subprocess
    from pathlib import Path
    ТЕКА = Path(__file__).resolve().parent
    РЕПО = ТЕКА.parents[3]
    батарея = json.loads((ТЕКА / 'батарея.json').read_text(encoding='utf-8'))
    assert len(батарея) == 6 and all(р['код'] == 0 for р in батарея), батарея
    for файл in sorted(ТЕКА.rglob('*')):
        if файл.suffix in ('.txt', '.json'):
            байти = файл.read_bytes()
            текст = байти.decode('utf-16' if байти.startswith(b'\xff\xfe') else 'utf-8-sig')
            # Єдине кодування й кінці рядків; відкидаються лише кінцеві пробіли журналу.
            текст = '\n'.join(р.rstrip() for р in текст.splitlines()).rstrip() + '\n'
            файл.write_text(текст, encoding='utf-8', newline='\n')
    def число(ім):
        текст = (ТЕКА / ім).read_text(encoding='utf-8')
        return int(re.findall(r'^місць: (\d+)$', текст, re.M)[-1])
    п6 = lambda ім: int(re.findall(r'^п\.6 .*: (\d+)$', (ТЕКА / ім).read_text(encoding='utf-8'), re.M)[-1])
    стан = dict(база='519b052fb1bee0fe0c9d0cd196e7b08351d49b68',
                код=subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=РЕПО).decode().strip(),
                дерево_джерел=subprocess.check_output(['git', 'rev-parse', 'HEAD:джерела'], cwd=РЕПО).decode().strip(),
                межі=[число('прилад-до.txt'), число('прилад-після.txt')],
                п6=[п6('прилад-до.txt'), п6('прилад-після.txt')],
                промпти=[число('промпти-до.txt'), число('промпти-кінцеві.txt')],
                вікно=[число('вікно-до.txt'), число('вікно-після.txt')],
                батарея=батарея, повний_храповик='не зелений: незмінені прилади кольору й обличчя')
    assert стан['межі'] == [118, 98] and стан['п6'] == [20, 0]
    assert стан['промпти'] == [114, 110] and стан['вікно'] == [0, 0]
    (ТЕКА / 'підсумок.json').write_text(json.dumps(стан, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')
    паспорт = РЕПО / 'аудит/корені/Е2-межі.md'
    давній = паспорт.read_text(encoding='utf-8').rstrip()
    допис = 'Перевірка завершеної батареї 2026-11-03 UTC: **6/6**, розділи гейтів **575/0/0**, контракти й показ — код 0. Після викладення архівів прилад Е2-вікно **0 → 0** на голові й дереві з тим самим джерельним кодом бази (SHA дерева `джерела/` 4e12166af3a99d342bb22f132079288fdd779362). Перші невдалі журнали збережені окремо; підсумок містить лише завершені команди. Загальний храповик не оголошено зеленим: потрібна сумісна з Windows версія приладу кольору та завершений вимір обличчя в межах 900 с; чекає диспетчера/сесії лічби. Наряд, живе мірило й незалежне приймання лишаються.'
    if допис not in давній:
        паспорт.write_text(давній + '\n\n' + допис + '\n', encoding='utf-8', newline='\n')
    print(json.dumps({к: стан[к] for к in ('межі', 'п6', 'промпти', 'вікно')}, ensure_ascii=False))
    print('Батарея: 6/6; загальний храповик не зелений.')


if __name__ == '__main__':
    main()
