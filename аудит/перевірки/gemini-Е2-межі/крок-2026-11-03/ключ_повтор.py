"""Порівняти ключ пакета на перестановці полів паспорта, без перебору каталогу."""


def main():
    """Виконати перевірку або запис стану лише при прямому запуску."""
    import json, os, sys
    from pathlib import Path
    ТЕКА = Path(__file__).resolve().parent
    РЕПО = ТЕКА.parents[3]
    КОД = Path(sys.argv[1]) if len(sys.argv) > 1 else РЕПО / 'джерела'
    sys.path[:0] = [str(КОД), str(РЕПО / 'джерела')]
    import bridge as Б, міст_пакет as П
    вхід = json.loads((РЕПО / 'джерела/стенд_вх.json').read_text(encoding='utf-8'))
    ключі = []
    for паспорт in ({'бажання': ['a'], 'ошатність': ['1']}, {'ошатність': ['1'], 'бажання': ['a']}):
        д = Б._застосувати_паспорт(dict(вхід, паспорт=паспорт))
        F, T, зріст, kw = Б._збірка(д)
        ключі.append(П.ключ_пакета(д, F, T, None if д.get('гілка') is None else 0))
    print('Ключі однакові:', ключі[0] == ключі[1])
    assert ключі[0] == ключі[1], 'Походження не має міняти ключ від перестановки полів'


if __name__ == '__main__':
    main()
