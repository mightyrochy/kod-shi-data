"""Звірити всі групи вето, зняття останнього бажання, старі паспорти й записані коментарі."""
import copy
import json
import sys
from pathlib import Path

ТЕКА = Path(__file__).resolve().parent
КОД = ТЕКА.parents[3] / "джерела"
sys.path.insert(0, str(КОД))
import мовний_шар as М
import картка_запиту as К
import руки_без_коду as Р
import паспорт_поля as П


def main():
    """Зібрати факти переходів на тих самих межах, що викликає показ."""
    слова = "Робочий день в офісі. кросівки сукня без сукні без шкіри без принта без чорного без декольте"
    хід = lambda в, п: М.паспорт_з_шару(в, {}, паспорт_досі=п, слова_ходу=[слова])["паспорт"]
    річ = {"item_type": "sneakers", "quote": "кросівки"}
    межі = [{"item_type": "dress_generic", "quote": "без сукні"},
            {"fabric": "leather", "quote": "без шкіри"},
            {"slot": "shoes", "pattern": "print_generic", "quote": "без принта"},
            {"color_name": "black", "quote": "без чорного"},
            {"zone": "neckline", "quote": "без декольте"}]
    подія = {"wants": [річ], "vetoes": межі}
    п = хід({"occasion": "work", "place": "office",
             "quotes": {"occasion": "Робочий день", "place": "в офісі"}}, {})
    коментар = М.паспорт_з_коментаря(подія, п)["паспорт"]
    повтор = М.паспорт_з_коментаря(подія, коментар)["паспорт"]
    новий_уривок = М.паспорт_з_коментаря({"wants": [dict(річ, quote="хочу кросівки")]}, повтор)["паспорт"]
    assert len(новий_уривок["бажання_коди"]) == 1
    assert новий_уривок["бажання_коди"][0]["уривок"] == "хочу кросівки"
    assert хід({}, новий_уривок)["бажання_коди"] == новий_уривок["бажання_коди"]
    далі = хід({}, повтор)
    assert all(далі["вето"].get(г) for г in ("типи", "тканини", "принти", "кольори", "зони"))
    assert далі["вето_тверде"]["слоти"]["принт"] == ["взуття"]
    assert далі["бажання"] == ["кросівки"] and len(далі["бажання_коди"]) == 1
    assert "вето_тверде" not in далі["картка_запиту"] and К.факт(далі, "вето")["джерело"] == "reading"
    знято = хід({"retract": [річ] + межі}, далі)
    порожній = хід({}, знято)
    assert порожній["бажання"] == [] and порожній["бажання_коди"] == []
    assert not any(порожній["вето"][г] or порожній["вето_тверде"][г] for г in ("типи", "тканини", "принти", "кольори", "зони"))
    assert not К.факт(порожній, "бажання")
    старий = {"бажання": ["сукня"], "цитати_полів": {"бажання": "сукня"}, "вето": {}}
    оригінал = copy.deepcopy(старий)
    міграція = хід({}, М.паспорт_з_коментаря(подія, старий)["паспорт"])
    assert старий == оригінал and міграція["бажання"] == ["сукня", "кросівки"]
    assert К.факт(міграція, "бажання")["опори"][0]["уривок"] == "сукня"
    assert К.факт(міграція, "бажання")["уривок"] == "кросівки"
    assert [о.get("quote") for о in П.походження_поля(міграція, "бажання")["parts"]] == ["сукня", "кросівки"]
    переконання = хід({"beliefs": [межі[1]]}, {})
    assert переконання["вето"] == К.факт(переконання, "вето")["значення"]
    assert К.факт(переконання, "вето")["уривок"] == "без шкіри"
    assert М.паспорт_з_коментаря(подія)["чому"] == "no_scenario_passport: comment_limits_and_wishes_not_applied"
    дріт = Р.випадок_кодами(далі, "")
    assert дріт["refusals"]["prints"] == [{"code": "print_generic", "only_on": ["shoes"]}], дріт
    (ТЕКА / "приклад.json").write_text(json.dumps(далі, ensure_ascii=False, indent=1), encoding="utf-8")
    записи = []
    for шлях in sorted((КОД.parent / "аудит/проби/б1/ПІСЛЯ-Е3").glob("*/VIDPOVIDI/*коментар*.txt")):
        т = шлях.read_text(encoding="utf-8")
        if "── ВІДПОВІДЬ" not in т:
            continue
        відповідь = т.split("── ВІДПОВІДЬ", 1)[1].split("\n", 1)[1]
        в = М.прийняти_вхід("verdict_comment", відповідь).get("внутрішня") or {}
        ком = М.паспорт_з_коментаря(в, далі)["паспорт"]
        наступний = хід({}, ком)
        збіг = all(ком.get(к) == наступний.get(к) for к in ("бажання", "бажання_коди", "вето"))
        записи.append(dict(джерело=str(шлях.relative_to(КОД.parent)), збіг=збіг))
    (ТЕКА / "переходи.json").write_text(json.dumps(dict(записи=записи, дріт=дріт), ensure_ascii=False, indent=1), encoding="utf-8")
    print("Усі групи вето: 5/5; зняття останнього бажання: 1/1; старий паспорт: 1/1; переконання: 1/1.")
    print("Записаних коментарів:", len(записи), "збіг після порожнього ходу:", sum(з["збіг"] for з in записи))
    assert записи and all(з["збіг"] for з in записи)


if __name__ == "__main__":
    main()
