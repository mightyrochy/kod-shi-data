"""Незалежні виміри #1927: знімок каталогу, два кольори та тип невідомого.

Запуск: python відтворити.py <дерево git> <каталог|два|невідомо> [JSON знімка].
Працює без моделей; каталог читає лише з диска з лімітом фото 0.
"""
import json
import os
from pathlib import Path
import sys

дерево = Path(sys.argv[1]).resolve()
код = дерево / "джерела"
sys.path.insert(0, str(код))
os.chdir(код)
import colorspace as КС
import outfit as О
import колір_річ as КР
import композитор_річ as КП

режим = sys.argv[2]
if режим == "каталог":
    import feed
    import фід_каталог as ФК
    знімок = ФК.прочитати_каталог(feed.каталог_на_диску(), 0)
    Path(sys.argv[3]).write_text(json.dumps(знімок, ensure_ascii=False), encoding="utf-8")
    print("Записів:", len(знімок["каталог"]))
elif режим == "два":
    річ = dict(id="два", слот="верх", hex="#ff0000", colors=[
        dict(lab=КС.hx("#ff0000"), coverage=.7),
        dict(lab=КС.hx("#0000ff"), coverage=.3)])
    print("Lab елементів:", [е["lab"] for е in О.елементи([річ])])
    if len(sys.argv) > 3:
        каталог = json.loads(Path(sys.argv[3]).read_text(encoding="utf-8"))["каталог"]
        спотворення = []
        for р in каталог:
            # Верхній шар у приміщенні не дає елементів; інші слоти — штатним шляхом.
            if not р.get("colors") or р.get("слот") == "верхній_шар":
                continue
            річ = КП.у_річ(р, р["слот"], {})
            for колір, елемент in zip(річ["colors"], О.елементи([річ])):
                if колір.get("не_вимір") or колір.get("колір_не_вимір"):
                    continue
                очікуваний = КР.точка_кольору(колір)
                отриманий = КР.точка_кольору(елемент)
                if очікуваний and отриманий and КС.de00(очікуваний, отриманий) > 1:
                    спотворення.append((р["id"], round(КС.de00(очікуваний, отриманий), 2)))
        print("Речей зі спотворенням >1 ΔE00:", len(set(р[0] for р in спотворення)),
              "елементів:", len(спотворення), "перші:", спотворення[:3])
elif режим == "невідомо":
    import жнива_колір as Ж
    import фід_збагачення as ФЗ
    точка = КС.hx("#777777")
    слово, _ = Ж.слово_з_lab(точка)
    перший = dict(слово="червоний", hex="#ee1111", lab=КС.hx("#ee1111"),
                  частка=.7, колір_тип="вимір", тон=30)
    другий = dict(слово=слово, hex="#777777", lab=точка, частка=.3,
                  колір_тип="невідомо", тон=None, світлота=50, хрома=[0, 10])
    а, б, _ = Ж.звести_колір([перший, другий], "червоний", [])
    запис = {}
    ФЗ.накласти_колір(запис, dict(версія=2, колір_основний=а, колір_другий=б))
    print("Вихід жнив:", б["колір_тип"], б["слово"])
    print("Після накладання:", КР.тип_кольору(запис["колір_другий"]),
          КР.межі_кольору(запис["колір_другий"]))
    print("Свідок:", КР.не_вимір(запис["колір_другий"]))
else:
    raise SystemExit("Невідомий режим: " + режим)
