"""Перевірка доробки: дозволені коди, перестановки й збереження меж між ходами."""
import itertools
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(sys.argv[1]).resolve() / "джерела"))
import мовний_шар as М
import пакет_моделі as П
import дріт_моделі as Д


def паспорт(записи, досі=None):
    return М.паспорт_з_коментаря({"vetoes": записи}, паспорт_досі=досі or {"вето": {}, "бажання": []})["паспорт"]


рез = []
for поле, код in (("length", "midi"), ("feature", "large_print"),
                  ("pattern", "floral"), ("fabric", "wool"), ("color_name", "black")):
    слово = М._ВМ.ключ(поле, код)
    записи = [{"slot": сл, поле: код} for сл in ("outerwear", "dress")]
    for порядок in itertools.permutations(записи):
        п = паспорт(list(порядок))
        вето = п["вето_тверде"]
        дріт = Д.випадок(П.випадок_для_пакета(п, "")).get("refusals")
        очікувані = {"верхній_шар", "сукня"}
        assert set(вето["слоти"][слово]) == очікувані, (поле, вето)
        між = паспорт([порядок[1]], паспорт([порядок[0]]))["вето_тверде"]
        assert set(між["слоти"][слово]) == очікувані, (поле, між)
        рез.append({"поле": поле, "перший": порядок[0]["slot"], "вето": вето, "дріт": дріт})
    if поле != "color_name":
        for порядок in itertools.permutations([{поле: код}, записи[0]]):
            п = паспорт(list(порядок))
            assert слово not in п["вето_тверде"]["слоти"], п
            for а, б in ((порядок[0], порядок[1]), (порядок[1], порядок[0])):
                п = паспорт([б], паспорт([а]))
                assert слово not in п["вето_тверде"]["слоти"], п

print(json.dumps({"перестановок": len(рез), "результати": рез}, ensure_ascii=False, indent=2))
