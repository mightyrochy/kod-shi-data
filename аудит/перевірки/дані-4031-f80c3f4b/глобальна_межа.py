"""Чи не звужує уточнення слота загальну відмову від того самого кольору."""
import itertools
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(sys.argv[1]).resolve() / "джерела"))
import мовний_шар as М
import пакет_моделі as П
import дріт_моделі as Д

рез = []
for порядок in itertools.permutations([
    {"color_name": "black", "quote": "Не хочу чорного взагалі, чорну сукню теж."},
    {"slot": "dress", "color_name": "black", "quote": "Не хочу чорного взагалі, чорну сукню теж."},
]):
    прийнято = М.прийняти_вхід("verdict_comment", json.dumps({"vetoes": list(порядок)}, ensure_ascii=False), слова=порядок[0]["quote"])
    assert len(прийнято["внутрішня"].get("vetoes", [])) == 2, прийнято
    п = М.паспорт_з_коментаря(прийнято["внутрішня"], паспорт_досі={"вето": {}, "бажання": []})["паспорт"]
    тв = п["вето_тверде"]
    речі = [{"слот": с, "назва": "Чорна річ", "колір": "чорний", "кольори": ["чорний"], "ціна": 1000}
            for с in ("сукня", "верхній_шар")]
    рез.append({"записи": порядок, "прийнято": прийнято, "вето": тв,
                "дріт": Д.випадок(П.випадок_для_пакета(п, "")).get("refusals"),
                "відбір": {р["слот"]: П.жорстке_відсічення(р, вето=тв) for р in речі}})
print(json.dumps(рез, ensure_ascii=False, indent=2))
