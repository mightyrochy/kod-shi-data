"""Розрізняє відсутній Git-вхід архіву й доступний Git-вхід тієї самої голови."""
import json
from pathlib import Path
import sys

дерево, репо = (Path(p).resolve() for p in sys.argv[1:])
sys.path.insert(0, str(дерево / "джерела"))
import правила as П

голова = "f80c3f4b97185735a8457baf59fba91a47705ecf"
рез = {
    "архів_HEAD": П._є_вхід("HEAD"),
    "архів_нульова_база": П._є_вхід("0" * 40),
    "репозиторій_HEAD": П._є_вхід("HEAD", репо=str(репо)),
    "репозиторій_призначена_голова": П._є_вхід(голова, репо=str(репо)),
    "репозиторій_нульова_база": П._є_вхід("0" * 40, репо=str(репо)),
}
assert "git-дерево" in рез["архів_HEAD"]
assert "git-дерево" in рез["архів_нульова_база"]
assert рез["репозиторій_HEAD"] is None
assert рез["репозиторій_призначена_голова"] is None
assert "бази" in рез["репозиторій_нульова_база"]
print(json.dumps(рез, ensure_ascii=False, indent=2))
