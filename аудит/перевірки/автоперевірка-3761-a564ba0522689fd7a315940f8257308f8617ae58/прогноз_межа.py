"""Відтворює лічбу прогнозу PR на інтервалі штатного формату без запуску каталогу.

python прогноз_межа.py <тимчасове дерево голови PR>
Виконує незмінений останній цикл авторської проби, а відповідь звіряє зі справжнім читачем.
"""
import ast
import collections
import pathlib
import sys

дерево = pathlib.Path(sys.argv[1]).resolve()
sys.path.insert(0, str(дерево / "джерела"))
import колір_світлота as КС

файл = дерево / "аудит/проби/Е3_ч37_похибка_частки/читання.py"
код = ast.parse(файл.read_text(encoding="utf-8"))
джерело = "варіант перебору"
елемент = dict(площа=0.03, площа_межі=(0.02, 0.04), джерело_площі=джерело)
відповідь = КС.частка_понад(елемент, 0.03)
print("Штатний читач: інтервал [0.02, 0.04], поріг 0.03 →", відповідь)
журнал = [((0, 165), "читач", 0.03, джерело, 0.03, "межі")]
print("Незмінений цикл прогнозу читання.py: так/ні (пари з читанням; усі читання потрібного джерела):")
остання = ast.Module(body=[код.body[-1]], type_ignores=[])
exec(compile(остання, str(файл), "exec"), dict(журнал=журнал, дж=джерело, collections=collections))
assert відповідь == "невідомо"
