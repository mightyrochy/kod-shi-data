"""Незалежна проба: python проба.py <дерево джерел> <мітка>. Моделей не викликає."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(sys.argv[1]).resolve() / "джерела"))
import мовний_шар as М
import паспорт_поля as П
import паспорт_нагоди as Н
import міст_пакет as Б

def друк(тип, **дані):
    print(json.dumps(dict(дерево=sys.argv[2], тип=тип, **дані), ensure_ascii=False))

попередній = None
for слова, смуга in (("+12 °C", "cool"), ("мінус десять", "deep_frost")):
    вхід = dict(weather_band=смуга, quotes=dict(weather_band=слова))
    вихід = М.паспорт_з_шару(вхід, {}, слова_ходу=слова, паспорт_досі=попередній)
    паспорт = вихід["паспорт"]
    факт = паспорт["картка_запиту"]["смуга_погоди"]
    друк("хід", слова=слова, очікувана_смуга=смуга, смуга=паспорт.get("смуга_погоди"),
         факт=факт, сила=П.сила_факту(факт), на_її_словах=П.на_її_словах(факт),
         записано=вихід["записано"], цитати=паспорт.get("цитати_полів"),
         походження=П.походження_поля(паспорт, "смуга_погоди"),
         шапка=Н.паспорт_шматками_людині(паспорт))
    попередній = паспорт

давній = {"смуга_погоди": "cool", "картка_запиту": {"смуга_погоди":
          dict(значення="cool", джерело="reading", уривок="+12 °C")}}
виправлений = М.паспорт_з_шару(dict(weather_band="deep_frost", quotes=dict(weather_band="мінус десять")),
                              {}, паспорт_досі=давній, слова_ходу="мінус десять")["паспорт"]
друк("давня_картка", очікувана_смуга="deep_frost", смуга=виправлений["смуга_погоди"],
     факт=виправлений["картка_запиту"]["смуга_погоди"])

for смуга in ("deep_frost", "frost", "cold", "cool", "mild", "warm", "hot"):
    друк("слоти", смуга=смуга, слоти=sorted(Б.обовязкові_слоти(dict(смуга_погоди=смуга))))
