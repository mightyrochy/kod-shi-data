# -*- coding: utf-8 -*-
"""Порівнює повний обсяг незміненого приладу на двох комітах.

З кореня: python -X utf8 аудит/перевірки/доробка-2963/відтворити.py [база] [голова] [JSON-вихід].
Тимчасові копії лише JS/HTML створюються в TEMP; код продукту не виконується.
"""
import json
from pathlib import Path
import subprocess
import sys
import tempfile

РЕПО = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(РЕПО / 'джерела/прилади'))
from е2_обробники import граф
from корінь_е2_усе_з_розмови import ДАНІ, вимір


def git(*арг):
    """Читає байти Git без зміни робочого дерева."""
    return subprocess.run(['git', '-C', str(РЕПО), *арг], capture_output=True, check=True).stdout


def зняти(коміт):
    """Віддає незміненому приладу всі JS/HTML заданого коміту."""
    with tempfile.TemporaryDirectory(prefix='е2-порівняння-') as тека:
        for назва in git('ls-tree', '-rz', '--name-only', коміт, '--', 'джерела/').decode('utf-8').split('\0'):
            if not назва or Path(назва).suffix not in ('.js', '.mjs', '.html'):
                continue
            шлях = Path(тека) / назва
            шлях.parent.mkdir(parents=True, exist_ok=True)
            шлях.write_bytes(git('show', коміт + ':' + назва))
        дані = граф(тека)
        результат = вимір(дані, json.loads(ДАНІ.read_text(encoding='utf-8-sig')))
        return dict(коміт=git('rev-parse', коміт).decode().strip(), файли=дані['файли'],
                    місць=len(результат['місця']), обробників=len(результат['обробники']),
                    функцій=len(результат['функції']), результат=результат, граф=дані)


def ключ(місце):
    """Порівнює функцію й дію без залежності від зсуву рядків."""
    адреса, назва = місце['функція'].split(' ', 1)
    return адреса.rsplit(':', 1)[0], назва, місце['назва']


def контексти(база, голова):
    """Показує втрату виключень за незміненого власного відбитка обробника."""
    старі = {о['ключ']: о for о in база['результат']['обробники']}

    def досяжні(дерево, ключ):
        функції = дерево['граф']['функції']
        початок = next(ф['ід'] for ф in функції if ф['файл'] + ':' + ф['відбиток'] == ключ)
        черга, бачені = [початок], set()
        while черга:
            і = черга.pop()
            if і in бачені:
                continue
            бачені.add(і)
            черга.extend(функції[і]['ребра'])
        return {(функції[і]['файл'], функції[і]['назва'], функції[і]['відбиток']) for і in бачені}

    записи = []
    for о in голова['результат']['обробники']:
        було = старі.get(о['ключ'])
        if о['стан'] == 'місце' and було and було['стан'] == 'не місце':
            зміни = досяжні(голова, о['ключ']) - досяжні(база, о['ключ'])
            записи.append(dict(обробник=о['обробник'], ключ=о['ключ'],
                колишнє_виключення=було.get('причина'), нові_чи_змінені_досяжні_функції=[
                    dict(файл=ф, функція=н, відбиток=в) for ф, н, в in sorted(зміни)]))
    return записи


def main():
    """Друкує числа, повний перелік нових груп і зниклі групи."""
    база = зняти(sys.argv[1] if len(sys.argv) > 1 else '067d98cc1f43782566e8b10117411a898a28b4d7')
    голова = зняти(sys.argv[2] if len(sys.argv) > 2 else 'beff755ac9f22b3d38e09635c6787b36e20569a2')
    старі, нові = ({ключ(м) for м in д['результат']['місця']} for д in (база, голова))
    вивід = dict(база={к: з for к, з in база.items() if к not in ('результат', 'граф')},
                  голова={к: з for к, з in голова.items() if к not in ('результат', 'граф')},
                  додано=[м for м in голова['результат']['місця'] if ключ(м) not in старі],
                  зникло=[м for м in база['результат']['місця'] if ключ(м) not in нові])
    виключення = контексти(база, голова)
    текст = json.dumps(вивід, ensure_ascii=False, indent=2) + '\n'
    if len(sys.argv) > 3:
        Path(sys.argv[3]).write_text(текст, encoding='utf-8')
        Path(sys.argv[3]).with_name('контексти.json').write_text(
            json.dumps(виключення, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f"місць: {база['місць']} → {голова['місць']}; додано: {len(вивід['додано'])}; зникло: {len(вивід['зникло'])}")
    print(f"файлів: {len(база['файли'])} → {len(голова['файли'])}; обробників: {база['обробників']} → {голова['обробників']}")
    print('Обробників із незміненим відбитком, але втраченим виключенням:', len(виключення))
    for м in вивід['додано']:
        print('+', м['функція'], '—', м['назва'])
    for м in вивід['зникло']:
        print('-', м['функція'], '—', м['назва'])


if __name__ == '__main__':
    main()
