"""Незалежна лічба каталогу та збереження точок сегментів на шляху до суду."""
import json
import os
from pathlib import Path
import sys

дерево = Path(sys.argv[1]).resolve()
sys.path.insert(0, str(дерево / "джерела"))
os.chdir(дерево / "джерела")
import feed as Ф
import фід_каталог as ФК
import чистка_каталогу as Ч
import колір_річ as К
import композитор_річ as С
import outfit as О
import colorspace as Ц
import palettes as П

Ч.забезпечити_чистим("каталог_повний.xml")
знімок = ФК.прочитати_каталог(Ф.каталог_на_диску(), 0)
каталог = знімок["каталог"]
Path(sys.argv[2]).write_text(json.dumps(знімок, ensure_ascii=False), encoding="utf-8")
зникло, спотворено, сегментів = [], [], 0
метал_відсіяно, певний_відсіяно = [], []
for р in каталог:
    if р.get("colors") and р.get("слот") != "верхній_шар":
        for колір, елемент in zip(р["colors"], О.елементи([С.у_річ(р, р["слот"], {})])):
            точка = К.точка_кольору(колір)
            if точка is None:
                continue
            сегментів += 1
            вихід = К.точка_кольору(елемент)
            if вихід is None:
                зникло.append(р["id"])
            elif Ц.de00(точка, вихід) > 1:
                спотворено.append(р["id"])
    if К.тип_кольору(р) == "інтервал" and р.get("метал") == "золото" and П.колір_металу(р):
        q = dict(метал="золото")
        if not Ф.описує_річ(р, q, вікно=К.вікно_речі(р)):
            метал_відсіяно.append(р["id"])
            if П.метал_меж(р, р.get("слот"), р.get("тип")) == "так":
                певний_відсіяно.append(р["id"])
print(json.dumps(dict(записів=len(каталог),
    типи={т: sum(К.тип_кольору(р) == т for р in каталог) for т in ("вимір", "інтервал", "невідомо")},
    невимір_з_lab=sum(bool(р.get("lab")) for р in каталог if К.тип_кольору(р) != "вимір"),
    сегментів=сегментів, зникло=зникло, спотворено=спотворено,
    золотих_інтервалів_відсіяно=len(метал_відсіяно),
    певних_металевих_інтервалів_відсіяно=len(певний_відсіяно),
    приклади_відсіяних=метал_відсіяно[:5]), ensure_ascii=False, indent=2))
