"""Перевірка рядка золота на збереженому каталозі без повторного читання фіду."""
import json
from pathlib import Path
import sys
sys.path.insert(0, str(Path(sys.argv[1]) / "джерела"))
import колір_річ as К
import palettes as П
import feed as Ф
import композитор_слоти as С

кат = json.loads(Path(sys.argv[2]).read_text(encoding="utf-8"))["каталог"]
золото = П.ЗОЛОТО
q = dict(L_min=золото["L"][0], L_max=золото["L"][1],
    C_min=золото["C"][0], C_max=золото["C"][1], h_from=золото["дуга"][0], h_to=золото["дуга"][1],
    нейтраль=False, метал="золото", роль="метал_палітри:золото")
рез = []
for р in кат:
    if К.тип_кольору(р) != "інтервал" or р.get("метал") != "золото" or not П.колір_металу(р):
        continue
    м = К.межі_кольору(р)
    метали = sorted({П.метал_речі(т) or "не метал" for т in К.точки_вікна(м)})
    рядок = dict(q, слот=р["слот"])
    частка = Ф.частка_вікна(м, рядок)
    описує = Ф.описує_річ(р, рядок, вікно=К.вікно_речі(р))
    if not описує:
        рез.append(dict(id=р["id"], слот=р["слот"], метали=метали, частка=частка))
print(json.dumps(dict(відсіяно=len(рез), певне_золото=sum(р["метали"] == ["золото"] for р in рез),
    перетин_рядка=sum(р["частка"] > 0 for р in рез),
    певний_метал=[р for р in рез if "не метал" not in р["метали"]]), ensure_ascii=False, indent=2))
