"""Лічба фактично завершених команд; ненульові коди не приховуються."""
import json
from pathlib import Path

тека = Path(__file__).resolve().parent
р = json.loads((тека / "результати.json").read_text(encoding="utf-8"))
батарея = {"дим", "живий_шлях", "протокол", "розділи", "контракти", "показ"}
аст = [з for з in р if з["назва"].startswith("поділ_")]
цільові = [з for з in р if з["назва"].startswith("колір_тип_213_")]
результат = dict(команд=len(р), код_0=sum(з["код"] == 0 for з in р),
    батарея={з["назва"]: з["код"] for з in р if з["назва"] in батарея},
    аст_команд=len(аст), аст_код_0=sum(з["код"] == 0 for з in аст),
    цільових_команд=len(цільові), цільових_код_0=sum(з["код"] == 0 for з in цільові),
    ненульові=[dict(назва=з["назва"], код=з["код"]) for з in р if з["код"] != 0])
текст = json.dumps(результат, ensure_ascii=False, indent=2)
(тека / "підсумок.json").write_text(текст, encoding="utf-8")
print(текст)
