"""Зберігає завершені виводи одним архівом і складає покажчик команд."""
import gzip, json, sys
from pathlib import Path
д = Path(sys.argv[1])
записи = json.loads((д/'команди.json').read_text(encoding='utf-8'))
assert len(записи) == 42
файли = sorted(д.glob('команда-*.txt'))
assert len(файли) == 42
with gzip.open(д/'проби-і-батарея.txt.gz', 'wt', encoding='utf-8') as архів:
    for ф in файли:
        текст = ф.read_text(encoding='utf-8')
        assert '\nКОД: ' in текст, ф
        архів.write('\n===== '+ф.name+' =====\n'+текст)
залишити = {'команда-01.txt','команда-28.txt','команда-37.txt','команда-41.txt','команда-42.txt'}
for ф in файли:
    if ф.name not in залишити:
        ф.unlink()
for з in записи:
    if з['вивід'] not in залишити:
        з['розділ_архіву'] = з['вивід']
        з['вивід'] = 'проби-і-батарея.txt.gz'
(д/'команди.json').write_text(json.dumps(записи,ensure_ascii=False,indent=2),encoding='utf-8')
рядки = ['# Команди перевірки f10a9cd27c2fb4dcc7096a8702a1d485ab837a16', '', 'Повний дослівний вивід усіх запусків — у `проби-і-батарея.txt.gz`; кожен розділ має початкове ім’я `команда-NN.txt`, теку, команду та код виходу. Індекс із часом — `команди.json`. NODE_OPTIONS і PYTHONPATH обгортки не змінювалися.', '', '| № | Команда | Код | Секунд |', '|---|---|---:|---:|']
for з in записи:
    команда = ' '.join(['python' if з['команда'][0].endswith('python.exe') else з['команда'][0]]+з['команда'][1:])
    рядки.append(f'| {з["номер"]} | `{команда}` | {з["код"]} | {з["секунд"]} |')
(д/'підсумок-команд.md').write_text('\n'.join(рядки)+'\n',encoding='utf-8')
print('Завершених запусків:',len(записи),'код 0:',sum(з['код']==0 for з in записи),'інший код:',sum(з['код']!=0 for з in записи))
for з in записи:
    if з['код']:
        print(з['номер'],з['команда'][1:],з['код'])
