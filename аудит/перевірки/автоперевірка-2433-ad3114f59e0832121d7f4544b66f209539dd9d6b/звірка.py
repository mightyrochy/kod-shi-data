"""Звіряє атрибуцію голови з базою й архівом; архів не замінює сирі події доби."""
import contextlib
import io
from pathlib import Path
import re
import runpy
import sys
from unittest.mock import patch


def головна():
    """Перевіряє всі рядки переліку та CLI на реконструйованих агрегатах."""
    база, голова = (Path(ш).resolve() for ш in sys.argv[1:])
    шлях = Path("джерела/прилади/корінь_пк_дотримання.py")
    б, г = (runpy.run_path(str(к / шлях)) for к in (база, голова))
    перелік = голова / "аудит/корені/ПК-дотримання-правил-перелік.md"
    правила = г["таблиці_переліку"](перелік)[0]
    ролі = ("виконавець", "перевірка", "диспетчер", "менеджер", "ноутбук")
    рушії = ("Claude", "Codex", "agy")
    підсумок = {(код, р, ру): (10 * н + м + 1, м)
                for н, код in enumerate(г["ПРАВИЛА"], 1)
                for м, (р, ру) in enumerate((р, ру) for р in ролі for ру in рушії)}
    перевірок = 0
    for к in правила:
        роль, _, рушій = к[3].partition(" · ")
        очікувані_ролі = set(ролі) if роль == "усі" else set(роль.split(", "))
        if роль == "усі, крім менеджера":
            очікувані_ролі = set(ролі) - {"менеджер"}
        очікувані_рушії = set(рушії) if рушій == "усі" else set(рушій.split(", "))
        for р in ролі:
            for ру in рушії:
                assert г["стосується"](к, р, ру) == (р in очікувані_ролі and ру in очікувані_рушії), к
                перевірок += 1
        очікуване = []
        for код in re.findall(r"К\d+", к[6]):
            вибір = [пара for (пк, р, ру), пара in підсумок.items()
                     if пк == код and р in очікувані_ролі and ру in очікувані_рушії]
            очікуване.append(f"{код} {sum(п[1] for п in вибір)}/{sum(п[0] for п in вибір)}")
        assert г["за_рядком"](к, підсумок) == "; ".join(очікуване), к
    print(f"рядків: {len(правила)}; перевірок роль/рушій: {перевірок}; розбіжностей: 0")

    змішані = [г["Дія"](код, роль, "2026-10-30T01:00:00Z", True, "умовна", рушій)
               for код, роль, рушій in підсумок]
    рядки, _, _ = г["зведення"](змішані)
    assert len(рядки) == len(підсумок)
    assert all(р[4:6] == (1, 1) for р in рядки)
    print(f"змішане зведення: груп {len(рядки)}; змішувань ролей/рушіїв: 0")

    архів = (голова / "аудит/корені/ПК-дотримання-правил-вивід.txt").read_text(encoding="utf-8")
    розділ, групи, старі = "", [], {}
    for рядок in архів.splitlines():
        if рядок.startswith("-- "):
            розділ = рядок
        ч = рядок.split(" · ")
        if розділ.startswith("-- правило") and re.fullmatch(r"К\d+", ч[0]):
            групи.append(ч)
        elif розділ.startswith("-- за правилами"):
            старі[tuple(ч[:2])] = рядок
    очікувані_групи = [tuple(ч[:4]) + (int(ч[4]), int(ч[5]), ч[6]) for ч in групи]
    виводи = []
    for модуль, назва in ((б, "база"), (г, "голова")):
        дії = []
        for код, _, роль, рушій, _, _, інтервали in групи:
            for інтервал, порушень, кількість in re.findall(r"(\d+):(\d+)/(\d+)", інтервали):
                for н in range(int(кількість)):
                    д = модуль["Дія"](код, роль, "2026-10-30T01:00:00Z", н < int(порушень), "з агрегату")
                    д.інтервал = int(інтервал)
                    дії.append(д)
        рядки, дій, порушень = модуль["зведення"](дії)
        if назва == "база":
            рядки = [р[:3] + ("Claude",) + р[3:] for р in рядки]
        assert рядки == очікувані_групи
        вивід = io.StringIO()
        with patch.dict(модуль["головна"].__globals__, {
            "події": lambda _: [], "відбиток": lambda _: [],
            "аналіз": lambda роль, *_: ([д for д in дії if д.роль == роль], []),
        }), contextlib.redirect_stdout(вивід):
            код = модуль["головна"](["--перелік", str(перелік), "--диспетчер", "д", "--менеджер", "м"]
                                    + [п for р in ролі for п in ("--сесія", f"{р}=агрегат")])
        assert код == 0
        рядки_виводу = вивід.getvalue().splitlines()
        за_адресою = {tuple(р.split(" · ")[:2]): р for р in рядки_виводу if " · ролі " in р}
        виводи.append(за_адресою)
        print(f"{назва}: груп {len(рядки)}; порушень {порушень} з {дій}; CLI-рядків з кодом {len(за_адресою)}")
    for адреса, рядок in виводи[0].items():
        assert рядок == старі[адреса], (рядок, старі[адреса])
    зміни = [адреса for адреса in виводи[0] if виводи[0][адреса] != виводи[1][адреса]]
    assert зміни == [("CHATGPT.md:16–17", "К11")]
    print(f"архів/CLI бази: розбіжностей 0; змінених рядків голови: {len(зміни)}")
    for адреса in зміни:
        print("ДО:", виводи[0][адреса])
        print("ПІСЛЯ:", виводи[1][адреса])
    print("Сирі події доби цією пробою не відтворюються.")


if __name__ == "__main__":
    головна()
