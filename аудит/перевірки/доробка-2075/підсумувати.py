"""Звірити завершені коди серій, каталожне мірило й відомі давні відхилення."""
import json
from pathlib import Path


def головна():
    """Не зараховувати пропущені команди чи нові ненульові результати як успіх."""
    тека = Path(__file__).resolve().parent
    читати = lambda ім: json.loads((тека / ім).read_text(encoding="utf-8"))
    результати = читати("результати.json")
    серії = {р: {з["назва"]: з for з in результати if з["режим"] == р} for р in ("ДО", "ПІСЛЯ")}
    assert серії["ДО"].keys() == серії["ПІСЛЯ"].keys(), "Набори команд ДО й ПІСЛЯ різні або ще не завершені"
    батарея = {"дим", "живий_шлях", "протокол", "розділи", "контракти", "показ"}
    нові = {"колір_тип_213_добір_металу", "колір_тип_213_великі", "колір_тип_213_читачі"}
    вих = {}
    for р, серія in серії.items():
        assert all(ім in серія and серія[ім]["код"] == 0 for ім in батарея)
        assert all(ім in серія and серія[ім]["код"] == (1 if р == "ДО" else 0) for ім in нові)
        дозволені = {"pal_K-PAL-16"} | (нові if р == "ДО" else set())
        ненульові = {ім for ім, з in серія.items() if з["код"]}
        assert ненульові <= дозволені, (р, ненульові - дозволені)
        ast = [з for ім, з in серія.items() if ім.startswith("поділ_")]
        assert len(ast) == 14 and all(з["код"] == 0 for з in ast)
        вих[р] = dict(команд=len(серія), батарея_пройшла=6, AST_пройшли=len(ast), ненульові=sorted(ненульові))
    додаткові = читати("додаткові-результати.json")
    assert len(додаткові) == 14
    hex_спільний = читати("hex-спільний-результати.json")
    нейтраль_спільний = читати("нейтраль-спільний-результати.json")
    assert len(hex_спільний) == len(нейтраль_спільний) == 2
    assert all(з["код"] == 0 for з in hex_спільний + нейтраль_спільний)
    додаткові = [з for з in додаткові if з["назва"] not in {"колір_hex_вікна", "колір_майже_нейтраль"}] + hex_спільний + нейтраль_спільний
    assert all(з["код"] == 0 or з["назва"] in {"колір_прози_шар", "колір_ярлик_hex"} for з in додаткові)
    for ім in ("основа-результати.json", "заміна-суд-результати.json", "стенд-результати.json"):
        серія = читати(ім)
        assert len(серія) == 2 and all(з["код"] == 0 for з in серія)
    до, після = [читати(р + "-мірило.json") for р in ("ДО", "ПІСЛЯ")]
    assert до["втрачено_у_металевому_рядку"] == 138 and після["втрачено_у_металевому_рядку"] == 0
    assert до["разом_у_пулі"] == 1071 and після["разом_у_пулі"] == після["великих_червоних_у_каталозі"] == 1410
    assert до["типи"] == після["типи"]
    assert all(з["невимір_з_lab"] == з["хибних_K_COL_05"] == 0 and not з["ж_07553_K_COL_05"] for з in (до, після))
    екран = json.loads((тека / "екран/ПІСЛЯ.json").read_text(encoding="utf-8"))
    assert екран["clipped"] == 0 and len(екран["rows"]) == 5
    вих.update(додаткових_команд=len(додаткові), нових_проб=len(нові),
                нових_відхилень=0, без_входу=читати("стенд-відмінності.json")["без_входу"])
    (тека / "підсумок.json").write_text(json.dumps(вих, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(вих, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    головна()
