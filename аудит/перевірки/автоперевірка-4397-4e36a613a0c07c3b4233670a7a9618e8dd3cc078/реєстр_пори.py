"""Який реєстр справді голосує в двох емісіях K-WEA-07 на голові #4397."""
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(sys.argv[1]).resolve() / 'джерела'))
import суд_погода as П
import реєстр_сила as С
from реєстр_тіри import тір_правила

справжній = С._обмежити_тіром
виклики = []


def простежити(правило, сила, reg=None):
    if правило == 'K-WEA-07':
        виклики.append(dict(правило=правило, реєстр_пори=reg is П.РЕЄСТР_ПОРИ,
                             ключі_пори=[к for к in П.РЕЄСТР_ПОРИ if к in (reg or {})],
                             тір=тір_правила(правило, reg)))
    return справжній(правило, сила, reg)


С._обмежити_тіром = простежити
річ = dict(id='уггі', назва='Уггі', слот='взуття', тип='уггі')
результати = []
for новий_тір in ('T3', 'T1'):
    for запис in П.РЕЄСТР_ПОРИ.values():
        запис['t'] = новий_тір
    for назва, функція in [
        ('сезон_і_погода', lambda: П.сезон_і_погода([річ], смуга_погоди='hot')),
        ('сезон_без_градусів', lambda: П.сезон_без_градусів([], [річ], 'літо')),
    ]:
        виклики.clear()
        вихід = [з for з in функція() if з['правило'] == 'K-WEA-07']
        результати.append(dict(емісія=назва, t_двох_констант=новий_тір,
                               виклики=list(виклики), знахідок=len(вихід)))
print(json.dumps(результати, ensure_ascii=False, indent=2))
