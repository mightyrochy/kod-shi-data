"""Дробові L*: сирий K-HOS-02 і справжній вихід вердикту моделі, без виклику моделі."""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(sys.argv[1]).resolve() / 'джерела'))
import суд_погода as П
import вердикт_моделі as В

вихід = []
for світлота in (25, 29, 29.4, 29.5, 29.75, 29.9, 30, 30.1, 30.25, 30.5, 30.6, 31, 35):
    речі = [dict(id='колготи', назва='Колготки', слот='колготи', L=світлота),
            dict(id='низ', назва='Спідниця', слот='низ', L=50),
            dict(id='взуття', назва='Черевики', слот='взуття', L=10)]
    сирі = [з for з in П.панчішні(речі) if з['правило'] == 'K-HOS-02']
    рядки, вето = В.знахідки_вердикту(сирі, '1')
    вихід.append(dict(L_к=світлота, Δ=abs(abs(світлота-10)-abs(світлота-50)),
                      сила=сирі[0]['сила'], вага=сирі[0]['сила_нп'],
                      рядків_вердикту=len(рядки), вето=вето))
print(json.dumps(вихід, ensure_ascii=False, indent=2))
