"""Незалежна проба 11330: звичайний імпорт підмодуля пакета приховує помічника.

Запуск: python <цей файл> <дерево голови PR #2267>.
Використовує лише конструктор тимчасових git-дерев стенда, очікування й дані — перевірки.
"""
import importlib.util
import pathlib
import sys

if __name__ == '__main__':
    дерево = pathlib.Path(sys.argv[1]).resolve()
    спец = importlib.util.spec_from_file_location(
        'стенд', дерево / 'джерела/прилади/стенд_храповика_кореня.py')
    стенд = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(стенд)
    код = 'джерела/код.txt'
    п = 'джерела/прилади/'
    паспорт = 'аудит/корені/Пакет.md'
    база = {
        паспорт: 'прилад: ' + п + 'лічба.py\nбаза: ' + п + 'пакет\n',
        п + 'лічба.py': "from пакет.лічба import лічи\nprint('місць:', лічи())\n",
        п + 'пакет/__init__.py': '',
        п + 'пакет/лічба.py': (
            "from спільне import МІТКА\n"
            "def лічи():\n"
            "    return open('джерела/код.txt', encoding='utf-8').read().count(МІТКА)\n"),
        п + 'спільне.py': "МІТКА = 'МІСЦЕ'\n",
        код: 'МІСЦЕ\n' * 5,
    }
    голова = {п + 'спільне.py': "МІТКА = 'НІЩО'\n", код: 'МІСЦЕ\n' * 10}
    результат, вивід = стенд.прогнати(база, голова, стенд.ХРАПОВИК)
    print('Справжніх місць: 5 → 10; помічник ослаблено звичайним статичним імпортом.')
    print('Очікувано: код 1, помічник поза «база:» або «різними PR».')
    print(f'Фактичний код: {результат}')
    print(вивід.partition('\n[підсумок]\n')[0].strip())
    база[паспорт] += 'база: ' + п + 'спільне.py\n'
    контроль, текст = стенд.прогнати(база, голова, стенд.ХРАПОВИК)
    print(f'Контроль: помічник явно в «база:», код {контроль}.')
    print(next((р for р in текст.splitlines() if 'різними PR' in р), текст))
    sys.exit(0 if результат == 0 and 'місць 5 → 0' in вивід and контроль == 1 else 1)
