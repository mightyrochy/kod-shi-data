"""Друкує межі цілої двоколірної речі після відмови від коду головного сегмента."""
import json, pathlib, sys
sys.stdout.reconfigure(encoding="utf-8")
джерела = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parents[3] / "джерела"
sys.path.insert(0, str(джерела.resolve()))
import surface as П, жнива_колір as Ж, колір_річ as К, verify as В, colorspace as С


def main():
    """Справжні вимір поверхні та читач, без підміни їхніх функцій."""
    білий, чорний = (237, 237, 237), (48, 48, 48)
    пікселі = [білий if x < 60 else чорний for y in range(100) for x in range(100)]
    поверхня = П.виміряти(пікселі, 100, 100, [1] * 10000, клас_маски="ATR", поправка=False)
    головний = поверхня["сегменти"][0]
    зведений = Ж.звести_колір(поверхня["сегменти"], None, ["чорний"])[0]
    print(json.dumps(dict(придатна=поверхня["придатна"], візерунок=поверхня["візерунок"],
        тип_головного=К.тип_кольору(головний), слово_зведеного=зведений["слово"],
        тип_зведеного=К.тип_кольору(зведений), точка=К.точка_кольору(зведений),
        межі_зведеного=К.межі_кольору(зведений), вікно_крамниці=В.вікно_певне("чорний"),
        L_другого=С.to_lab(чорний)[0], свідок=К.провенанс_кольору(зведений)), ensure_ascii=False))


if __name__ == "__main__":
    main()
