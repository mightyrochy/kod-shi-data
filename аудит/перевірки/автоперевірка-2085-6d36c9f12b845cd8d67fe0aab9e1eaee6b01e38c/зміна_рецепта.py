"""Відтворює пропуск завершеної крамниці після зміни JSON-рецепта."""
from pathlib import Path
import tempfile
from власні_випадки import магазин, прочитати, json_прохід


def main():
    """Порівнює керівник обходу й прямий запуск на тому самому новому рецепті."""
    for сім in ("woo", "shopify"):
        with tempfile.TemporaryDirectory(prefix="review-2085-recipe-") as ж:
            магазин(ж, сім)
            старий = json_прохід.прочитати_стан(ж, "review.test")["підпис"]
            запити_обходу = магазин(ж, сім, через_обхід=True, версія=2)
            файл = Path(ж) / "сирі/review.test.jsonl"
            адрес_обходу = len({з["url"] for з in прочитати(файл)[0]})
            підпис_обходу = json_прохід.прочитати_стан(ж, "review.test")["підпис"]
            запити_прямі = магазин(ж, сім, версія=2)
            адрес_прямі = len({з["url"] for з in прочитати(файл)[0]})
            підпис_прямий = json_прохід.прочитати_стан(ж, "review.test")["підпис"]
            print(f"{сім}: змінено пошук API на /v2; обхід HTTP={запити_обходу}, адрес={адрес_обходу}/12, "
                  f"лишив старий підпис={підпис_обходу == старий}; прямий HTTP={запити_прямі}, "
                  f"адрес={адрес_прямі}/12, новий підпис={підпис_прямий != старий}")
            assert запити_обходу == [] and адрес_обходу == 6 and підпис_обходу == старий
            assert запити_прямі == [1, 2, 3, 4] and адрес_прямі == 12 and підпис_прямий != старий
    print("З1 відтворено: 2/2 JSON-сімейства; обхід пропускає новий рецепт, прямий запуск його приймає.")


if __name__ == "__main__":
    main()
