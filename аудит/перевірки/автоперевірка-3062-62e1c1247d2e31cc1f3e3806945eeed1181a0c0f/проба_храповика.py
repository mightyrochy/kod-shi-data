"""Відтворює храповик лише призначеного кореня на дереві перевіреної голови.

Запуск: python проба_храповика.py <дерево голови PR #3062>.
Лічба, накладання приладу голови на базу та перевірка змін — незмінені функції храповика.
"""
from pathlib import Path
import sys

дерево = Path(sys.argv[1]).resolve()
sys.path.insert(0, str(дерево / "джерела" / "прилади"))
import храповик_кореня as Х

назва = "Е2-втрата-слова"
читати_базу = Х.паспорти_бази
читати_голову = Х.паспорти_голови
Х.паспорти_бази = lambda *а: {к: з for к, з in читати_базу(*а).items() if к == назва}
Х.паспорти_голови = lambda *а: {к: з for к, з in читати_голову(*а).items() if к == назва}
рядки, помилки, _ = Х.храповик(str(дерево), "39efd63c4692f04c5e95889d96c62f932e0c623f")
print("\n".join(рядки))
print("\n".join(помилки))
raise SystemExit(bool(помилки))
