"""Граничні світлоти колготок: запускати окремо на джерелах ДО й ПІСЛЯ."""
import json, pathlib, sys
sys.path.insert(0, str(pathlib.Path(sys.argv[1]).resolve() / 'джерела'))
import суд_погода as П
вихід = []
for L_к in [25, 29, 29.5, 30, 30.5, 31, 35]:
    речі = [dict(id='колготи', назва='Колготки', слот='колготи', L=L_к),
            dict(id='низ', назва='Спідниця', слот='низ', L=50),
            dict(id='взуття', назва='Черевики', слот='взуття', L=10)]
    з = next(з for з in П.панчішні(речі) if з['правило'] == 'K-HOS-02')
    вихід.append(dict(L_к=L_к, сила=з['сила'], вага=з['сила_нп'],
                      джерело=з['сила_нп_джерело'], суть=з['суть']))
print(json.dumps(вихід, ensure_ascii=False, indent=2))
