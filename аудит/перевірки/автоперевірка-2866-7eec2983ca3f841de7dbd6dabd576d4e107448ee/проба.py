# -*- coding: utf-8 -*-
"""Незалежне відтворення двох зауважень #2866 та перевірка його голови.

Запуск з кореня гілки звіту: python <цей файл> --дерево <дерево PR> --база <дерево бази>.
Додатково --батарея виконує батарею з аудит/КОД.md після npm ci у дереві PR.
Моделі й платні API не використовуються. Результат пишеться поруч із пробою.
"""
import argparse
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile


def модуль(імя, шлях):
    """Завантажує конкретний файл приладу з його власним ім'ям."""
    опис = importlib.util.spec_from_file_location(імя, шлях)
    м = importlib.util.module_from_spec(опис)
    sys.modules[імя] = м
    опис.loader.exec_module(м)
    return м


def головна():
    """Виконує скінченний набір проб, зберігаючи команди, коди та виводи."""
    п = argparse.ArgumentParser()
    п.add_argument('--дерево', type=Path, required=True)
    п.add_argument('--база', type=Path, required=True)
    п.add_argument('--батарея', action='store_true')
    а = п.parse_args()
    голова, база = а.дерево.resolve(), а.база.resolve()
    прилади = голова / 'джерела/прилади'
    sys.path.insert(0, str(прилади))
    os.environ['PYTHONIOENCODING'] = 'utf-8'
    результат = {'голова': '7eec2983ca3f841de7dbd6dabd576d4e107448ee', 'проби': {}, 'команди': []}
    старий_sha = '69c82b1af8b6525af3cabc8303f795f8a97d83b4'
    шлях = 'джерела/прилади/корінь_е3_заміна_з_перевіркою.py'
    ремонт = "def ф(є):\n    return зн(**({'ремонт': 'замінити пальто'} if є else {'ремонт': 'виміряти довжину'}))\n"
    суд = '''def заміна(кандидат, інший_новий_образ, межі, явний_вибір):
    вердикт = суд(інший_новий_образ)
    if not вердикт['пройдено']:
        return None
    if not у_межах(кандидат, межі):
        return None
    if not зберігає_вибір(кандидат, явний_вибір):
        return None
    return dict(готово=True, річ=кандидат, вердикт=вердикт)
'''
    безпечний = суд.replace('    вердикт = суд(інший_новий_образ)',
                           '    новий_образ = [*інший_новий_образ, кандидат]\n    вердикт = суд(новий_образ)')
    with tempfile.TemporaryDirectory(prefix='незалежна_2866_') as т:
        тека = Path(т)
        (тека / 'джерела').mkdir()
        старий = тека / 'старий.py'
        старий.write_bytes(subprocess.check_output(['git', '-C', str(голова), 'show', f'{старий_sha}:{шлях}']))
        for ім, файл in [('до', старий), ('після', голова / шлях)]:
            м = модуль('прилад_' + ім, файл)
            результат['проби'][ім] = {}
            for назва, код in [('умовний_ремонт', ремонт), ('чужий_склад', суд),
                               ('повний_контракт', безпечний),
                               ('зміна_кандидата', безпечний.replace('    return dict', '    кандидат = інший\n    return dict'))]:
                (тека / 'джерела/шлях.py').write_text(код, encoding='utf-8')
                кандидати, _ = м.сканувати(тека)
                місця = [к for к in кандидати if к.умови]
                результат['проби'][ім][назва] = {'місць': len(місця), 'умови': [к.умови for к in місця]}
        х = модуль('храповик_перевірки', прилади / 'храповик_кореня.py')
        паспорт = (голова / 'аудит/корені/Е3-заміна-з-перевіркою.md').read_text(encoding='utf-8')
        результат['паспорт'] = х.розібрати_паспорт(паспорт)
        результат['лічити_голова'] = х.лічити(str(голова), шлях, [])
        # Той самий прилад голови, а корінь обсягу — незмінене дерево бази.
        результат['лічити_база'] = х.лічити(str(голова), шлях, ['--корінь', str(база)])
    def команда(назва, аргументи, cwd):
        """Чекає завершення команди та записує її повний вивід."""
        вих = subprocess.run(аргументи, cwd=cwd, capture_output=True, env=dict(os.environ))
        запис = {'назва': назва, 'команда': аргументи, 'cwd': str(cwd), 'код': вих.returncode,
                 'stdout': вих.stdout.decode('utf-8', 'replace'), 'stderr': вих.stderr.decode('utf-8', 'replace')}
        результат['команди'].append(запис)
        print(f'{назва}: код {вих.returncode}', flush=True)
    команда('сім’я приладу', [sys.executable, 'джерела/прилади/тест_корінь_е3_заміна_з_перевіркою.py'], голова)
    if а.батарея:
        дж = голова / 'джерела'
        for назва, аргументи in [
            ('підготовка каталогу', [sys.executable, '-c', "import чистка_каталогу as ч, feed as Ф; print('фід:', ч.забезпечити_чистим('каталог_повний.xml')); print('фікстура:', Ф.каталог_на_диску('каталог_brief.xml'))"]),
            ('дим', [sys.executable, 'стенд_знімок.py', '--дим']),
            ('живий шлях', [sys.executable, 'тест_живого_шляху.py']),
            ('протокол', [sys.executable, 'тест_протоколу.py']),
            ('розділи гейтів', [sys.executable, 'прилади/розділи_гейтів.py']),
            ('контракти', [sys.executable, 'audit_contracts.py']),
            ('показ', ['node', 'тест_показу.js'])]:
            команда(назва, аргументи, дж)
    for назва, дерево in [('дошка голови', голова), ('дошка бази', база)]:
        команда(назва, [sys.executable, 'джерела/прилади/згорнути_дошку.py', '--лише-перевірити'], дерево)
    файл = Path(__file__).with_name('доказ.json')
    файл.write_text(json.dumps(результат, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({к: з for к, з in результат.items() if к != 'команди'}, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    головна()
