"""Незалежно звіряє весь обсяг записів із наряду; мережу не викликає."""
import json
import re
import sys
from pathlib import Path

корінь = Path(sys.argv[1]).resolve()
проби = корінь / 'аудит/проби'
файли = sorted((проби / 'б1/ПІСЛЯ-Е3').glob('*/вердикти.txt'))
файли += sorted(проби.glob('автоживий-*/**/вердикти.txt'))
записи = []
старі_зелені = старі_червоні = без_мережі = 0
for файл in файли:
    дані = json.loads(файл.read_text(encoding='utf-8'))
    фото = (файл.parent / 'знімки/фото_карток.txt').read_text(encoding='utf-8')
    стан = {рука: (int(усі), int(ок)) for рука, усі, ок in re.findall(
        r'рука (\d) · картинок (\d+), прийшло (\d+)', фото)}
    доказ = json.loads((файл.parent / 'знімки/доказ.json').read_text(encoding='utf-8'))
    лог = (файл.parent / 'лог.txt').read_text(encoding='utf-8')
    рядок = next(р for р in лог.splitlines() if 'руки 1–2: речі з фото й цінами' in р)
    старі_зелені += '✔' in рядок
    старі_червоні += '✗' in рядок
    без_мережі += '· без FOTO=1 мережі нема' in лог
    картки = []
    for прогін in дані['прогони']:
        for вердикт in прогін['вердикти']:
            рука = str(вердикт['рука'])
            речі = вердикт.get('речі_образу') or []
            картки.append({'рука': рука, 'речей': len(речі),
                           'фото': sum(bool(р.get('фото')) for р in речі),
                           'без_свого': sum(not р.get('фото') and not р.get('фото_усі') for р in речі),
                           'img': стан[рука][0], 'прийшло': стан[рука][1]})
    записи.append({'запис': файл.parent.relative_to(проби).as_posix(),
                   'FOTO': доказ['режим'].get('FOTO'), 'картки': картки})
руки = [к for з in записи for к in з['картки'] if к['рука'] in ('1', '2')]
підсумок = {'записів': len(записи), 'Е3': sum(з['запис'].startswith('б1/') for з in записи),
             'автоживих': sum(з['запис'].startswith('автоживий-') for з in записи),
             'карток_рук_1_2': len(руки), 'речей': sum(к['речей'] for к in руки),
             'з_адресою': sum(к['фото'] for к in руки), 'img': sum(к['img'] for к in руки),
             'завантажено': sum(к['прийшло'] for к in руки),
             'FOTO_0_явно': sum(з['FOTO'] == '0' for з in записи),
             'лог_без_мережі': без_мережі, 'лог_стара_зелена': старі_зелені,
             'лог_стара_червона': старі_червоні}
Path(sys.argv[2]).write_text(json.dumps(записи, ensure_ascii=False, indent=2), encoding='utf-8')
print(json.dumps(підсумок, ensure_ascii=False))
