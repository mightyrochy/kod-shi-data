"""Відтворити відсів золотого інтервалу штатним добором прикрас."""
import json
import os
from pathlib import Path
import sys


def головна():
    """Порівняти синтетичну пару та, за наявності, справжні записи каталогу."""
    корінь = Path(sys.argv[1]).resolve()
    sys.path.insert(0, str(корінь / "джерела"))
    os.chdir(корінь / "джерела")
    import feed
    import verify as В
    import palettes as П
    import композитор_слоти as С
    import фід_збагачення as З
    import колір_річ as К
    вікно = В.ЛЕКСИКОН["золотий"]
    новий = hasattr(К, "тип_кольору")
    р = dict(id="інтервал-золота", назва="Золоте намисто", слот="намисто", тип="намисто", метал="золото",
             lab=None if новий else tuple(П.центр(вікно)), колір_тип="інтервал",
             колір_не_вимір=З.не_вимір_кольору(вікно, "золотий", "shop_word"))
    м = dict(р, id="вимір-золота", lab=(70, 0, 40), колір_тип="вимір", колір_не_вимір=None)
    запит = dict(слот="намисто", метал="золото", L_min=0, L_max=100, C_min=0, C_max=100,
                 h_from=0, h_to=359)
    пул = С.кандидати_на_слот([р, м], [запит], "намисто", прикраси="золото")
    print("Типізований API:", новий)
    print("Метал палітри:", П.колір_металу(р))
    print("Описує інтервал:", feed.описує_річ(р if новий else р["lab"], запит, вікно=вікно))
    print("Частка вікна:", feed.частка_вікна(вікно, запит))
    print("Пул:", [(x["id"], bool(x.get("_вікно"))) for x in пул[0]])
    палітра = П.палітра_практична({}, самозвіт={"метал": "золото"})
    рядки = П.рядки_у_фід(dict(палітра_практична=палітра, слоти={"намисто": dict(L=(0, 100), C=(0, 100))}))
    золотий = next(q for q in рядки if q.get("метал") == "золото")
    print("Штатний золотий рядок:", золотий)
    print("Його частка:", feed.частка_вікна(вікно, золотий))
    print("Лише штатний золотий рядок, пул:", [x["id"]
          for x in С.кандидати_на_слот([р, м], [золотий], "намисто", прикраси="золото")[0]])
    print("Штатні рядки, пул:", [(x["id"], (x.get("_вікно") or {}).get("роль"))
          for x in С.кандидати_на_слот([р, м], рядки, "намисто", прикраси="золото")[0]])
    темні = П.рядки_у_фід(dict(палітра_практична=палітра, слоти={"намисто": dict(L=(30, 54), C=(0, 100))}))
    print("Штатні рядки темного слота, пул:", [(x["id"], (x.get("_вікно") or {}).get("роль"))
          for x in С.кандидати_на_слот([р, м], темні, "намисто", прикраси="золото")[0]])
    if len(sys.argv) > 2:
        каталог = json.loads(Path(sys.argv[2]).read_text(encoding="utf-8"))["каталог"]
        прикраси = [x for x in каталог if x.get("метал") == "золото" and x.get("слот") == "намисто"]
        пул = С.кандидати_на_слот(прикраси, рядки, "намисто", прикраси="золото")[0]
        print("Каталог золотих намист:", len(прикраси), "пул:", len(пул))
        print("Відібрані:", [(x["id"], К.точка_кольору(x) is None) for x in пул])
        print("Пропущені:", [(x["id"], П.колір_металу(x)) for x in прикраси if x["id"] not in {y["id"] for y in пул}])
        пул = С.кандидати_на_слот(прикраси, [золотий], "намисто", прикраси="золото")[0]
        print("Каталог, лише штатний золотий рядок:", [x["id"] for x in пул])


if __name__ == "__main__":
    головна()
