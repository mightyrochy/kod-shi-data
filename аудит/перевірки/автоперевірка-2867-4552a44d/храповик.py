"""Справжній храповик зі звуженням лише переліку паспортів до цільового кореня."""
from pathlib import Path
import sys

голова = Path(sys.argv[1]).resolve()
sys.path.insert(0, str(голова / 'джерела/прилади'))
import храповик_кореня as х

корінь = 'Річ-примірка-та-сама-людина'
for назва in ('паспорти_голови', 'паспорти_бази'):
    функція = getattr(х, назва)
    def лише_цільовий(*аргументи, функція=функція):
        return {к: в for к, в in функція(*аргументи).items() if к == корінь}
    setattr(х, назва, лише_цільовий)
рядки, помилки, стенд = х.храповик(str(голова), sys.argv[2])
print('\n'.join(рядки))
print('\n'.join(помилки))
print(f'червоних: {len(помилки)}; стенд: {стенд}')
sys.exit(bool(помилки))
