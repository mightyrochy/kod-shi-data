"""Чи міняє вибір насиченості й основи чип/стрічку (зразки гілок) — на дереві з argv[1]."""
import sys, json, pathlib
sys.path.insert(0, str(pathlib.Path(sys.argv[1]) / "джерела"))
import bridge as М
вхід = dict(шкіра=["#e8b99b"], очі="#56816b", волосся=["#70503b"], обхвати={}, зріст=168, самозвіт=dict(метал="золото"))
def зразки(вк):
    р = json.loads(М.палітри(dict(вхід, вибір_кольору=вк)))
    return {г["схема"]: (г.get("зразки"), [x["зразок"] for x in г.get("ролі", [])]) for г in р["гілки"]}
а = зразки({"насиченість": "приглушені"})
б = зразки({"насиченість": "насичені"})
for с in а:
    print(с, "| зразки однакові:", а[с][0] == б[с][0], "| ролі однакові:", а[с][1] == б[с][1], "|", а[с][0], б[с][0])
