"""Порівнює знімки base/head: збіг чипа з поєднанням, законність пар за кінцевими hex, повтори сімей, дифф брифу."""
import sys, json, gzip, pathlib, itertools
from collections import Counter
sys.path.insert(0, str(pathlib.Path(sys.argv[1]) / "джерела"))
import colorspace as КС, колір_річ as КР, колір_відношення as КВ, pipeline as К
base = json.loads(gzip.decompress(pathlib.Path(sys.argv[2]).read_bytes()))
head = json.loads(gzip.decompress(pathlib.Path(sys.argv[3]).read_bytes()))
КЛАС = {"аналогова": "analogous", "приглушена_комплементарна": "complementary", "тріада": "triadic"}
ПРИЙОМ = {"нейтрали+акцент": "нейтраль_плюс_акцент", "тональна": "тон_у_тон"}
def кольорові(hexи):
    р = []
    for x in hexи:
        lab = КС.hx(x); L, C, h = КС.lch(lab)
        if not К._нейтральний_тон(h, C, L): р.append((x, dict(lab=lab)))
    return р
def вади(схема, hexи):
    """Пари кольорових за кінцевим hex: та сама сім'я чи сила відношення < 0.5."""
    в = []
    кл = КЛАС.get(схема)
    for (ха, а), (хб, б) in itertools.combinations(кольорові(hexи), 2):
        сс = КР.та_сама_сім_я(а, б)
        с = КВ.сила(КР.запис_кольору(а), КР.запис_кольору(б), кл)[0] if кл else None
        if сс != "ні" or (кл and с < 0.5): в.append((ха, хб, сс, None if с is None else round(с, 2)))
    return в
for ім, дані in (("base", base), ("head", head)):
    збіг = 0; порожні = Counter(); вад_пер = Counter(); вад_пар = Counter(); приклади = {}
    аналог3 = аналог_повт = 0
    for п in дані:
        ок = True
        for г, пк in zip(п["гілки"], п["пакет"]):
            з = [x for x in (г["зразки"] or []) if x]
            if пк["поєднання"] is not None:
                пр = ПРИЙОМ.get(пк["базова"], пк["базова"])
                оч = [к["hex"] for к in (next((q for q in пк["поєднання"] if q["прийом"] == пр), {}) or {}).get("кольори", [])]
                ок &= з == оч
            if not з: порожні[г["схема"]] += 1; continue
            if г["схема"] == "аналогова" and len(з) == 3:
                аналог3 += 1
                аналог_повт += any(в[2] == "так" for в in вади("аналогова", з))
            схема = пк["базова"]
            if схема not in КЛАС: continue
            в = вади(схема, з)
            if в:
                вад_пер[г["схема"]] += 1; вад_пар[г["схема"]] += len(в)
                if ім == "head":
                    б = base[п["і"]]["пакет"]; було = any([к["hex"] for к in q["кольори"]] == з for x in б for q in (x["поєднання"] or []))
                    print("   вада", г["схема"], "база:", схема, "персона", п["і"], п["вхід"]["шкіра"][0], п["вхід"]["очі"], п["вхід"]["волосся"][0], п["вхід"]["самозвіт"]["метал"], з, в, "трійка була в поєднаннях бази:", було)
                приклади.setdefault(г["схема"], (п["і"], п["вхід"]["шкіра"][0], п["вхід"]["очі"], п["вхід"]["волосся"][0], п["вхід"]["самозвіт"]["метал"], з, в))
        збіг += ок
    print(f"== {ім}: чип=поєднання {збіг}/{len(дані)}; аналогових трійок {аналог3}, з повтором сім'ї {аналог_повт}")
    print("   порожні чипи:", dict(порожні), "усього", sum(порожні.values()))
    print("   чипів із вадою пари (персон·гілок):", dict(вад_пер), "пар:", dict(вад_пар))
    for с, пр in приклади.items(): print("   приклад", с, пр)
# дифф брифу
зм = Counter(); список = []
for б, г in zip(base, head):
    без_ан = not any(q["прийом"] == "аналогова" for q in (б["пакет"][0]["поєднання"] or []))
    змінено = [x["бриф"] for x in б["пакет"]] != [x["бриф"] for x in г["пакет"]]
    зм[("без_аналогової" if без_ан else "з_аналоговою") + ("_змінено" if змінено else "_незмінно")] += 1
    if змінено and not без_ан: список.append(б["і"])
print("== бриф ДО→ПІСЛЯ:", dict(зм), "змінені з аналоговою:", список[:20])
