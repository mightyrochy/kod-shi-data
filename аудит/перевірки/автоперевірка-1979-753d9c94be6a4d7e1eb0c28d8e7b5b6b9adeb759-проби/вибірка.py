"""Вибірка 32 персон (кожна 10-та сітки): час виклику, мисматч = базова схема на чипі, чутливість чипа до гами."""
import sys, json, pathlib, time, itertools, statistics
sys.path.insert(0, str(pathlib.Path(sys.argv[1]) / "джерела"))
import bridge as М
сітка = list(itertools.product(
    ("#f1d0b5", "#e8b99b", "#bb8561", "#8d573c", "#5a3a2a"),
    ("#3b2417", "#765336", "#9a803e", "#56816b", "#5c8499", "#687982", "#9c9e87"),
    ("#16110e", "#70503b", "#d4b887"), ("золото", "срібло", "обидва")))
М.палітри(dict(шкіра=["#000000"], очі="#3b2417", волосся=["#16110e"], обхвати={}, зріст=168))
т = []; мисм_одн = мисм = гама_одн = гілок = 0
for і in range(1, 315, 10):
    ш, о, в, м = сітка[і]
    вх = dict(шкіра=[ш], очі=о, волосся=[в], обхвати={}, зріст=168, самозвіт=dict(метал=м))
    t = time.perf_counter(); р = json.loads(М.палітри(вх)); т.append(time.perf_counter() - t)
    зр = {г["схема"]: г.get("зразки") for г in р["гілки"]}
    мисм += 1; мисм_одн += any(зр.get("контраст-мисматч") == зр.get(с) for с in ("тональна", "нейтрали+акцент"))
    а = json.loads(М.палітри(dict(вх, вибір_кольору={"насиченість": "приглушені"})))
    б = json.loads(М.палітри(dict(вх, вибір_кольору={"насиченість": "насичені"})))
    for га, гб in zip(а["гілки"], б["гілки"]):
        гілок += 1; гама_одн += га.get("зразки") == гб.get("зразки")
print(sys.argv[1][-4:], f"медіана {statistics.median(т):.2f} с; сума {sum(т):.1f} с; макс {max(т):.2f} с;",
      f"мисматч = базова схема {мисм_одн}/{мисм}; чип не змінився від гами {гама_одн}/{гілок} гілок")
