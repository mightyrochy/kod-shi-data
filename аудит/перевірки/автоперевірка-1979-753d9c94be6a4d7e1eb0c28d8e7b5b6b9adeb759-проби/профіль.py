import sys, pathlib, time, itertools
sys.path.insert(0, str(pathlib.Path(sys.argv[1]) / "джерела"))
import bridge as М, palettes as П
н = {"пп": 0, "пс": 0, "т_пс": 0.0}
ор_пп, ор_пс = П.палітра_практична, getattr(П, "поєднання_схеми", None)
def пп(*а, **к): н["пп"] += 1; return ор_пп(*а, **к)
П.палітра_практична = пп
if ор_пс:
    def пс(*а, **к):
        н["пс"] += 1; t = time.perf_counter(); р = ор_пс(*а, **к); н["т_пс"] += time.perf_counter() - t; return р
    П.поєднання_схеми = пс
М.палітри(dict(шкіра=["#000000"], очі="#3b2417", волосся=["#16110e"], обхвати={}, зріст=168))
for k in н: н[k] = 0
вх = dict(шкіра=["#e8b99b"], очі="#9a803e", волосся=["#16110e"], обхвати={}, зріст=168, самозвіт=dict(метал="золото"))  # персона 81
t = time.perf_counter(); М.палітри(вх); весь = time.perf_counter() - t
print(sys.argv[1][-4:], f"виклик {весь:.2f} с; палітра_практична × {н['пп']}; поєднання_схеми × {н['пс']}, у ній {н['т_пс']:.2f} с")
