"""Знімає 315 персон справжнього моста на дереві argv[1] у argv[2] (json.gz): зразки гілок, поєднання, бриф."""
import sys, json, gzip, pathlib, itertools
sys.path.insert(0, str(pathlib.Path(sys.argv[1]) / "джерела"))
import bridge as М, міст_основи as МО, palettes as П
ориг = МО.пакет
пакети = []
def запис(*а, **к):
    п = ориг(*а, **к); пакети.append(п); return п
МО.пакет = запис
out = []
сітка = itertools.product(
    ("#f1d0b5", "#e8b99b", "#bb8561", "#8d573c", "#5a3a2a"),
    ("#3b2417", "#765336", "#9a803e", "#56816b", "#5c8499", "#687982", "#9c9e87"),
    ("#16110e", "#70503b", "#d4b887"), ("золото", "срібло", "обидва"))
for і, (ш, о, в, м) in enumerate(сітка):
    пакети.clear()
    вх = dict(шкіра=[ш], очі=о, волосся=[в], обхвати={}, зріст=168, самозвіт=dict(метал=м))
    е = json.loads(М.палітри(вх))
    г_п = пакети[-1]["палітри"]["розвилка"]
    out.append(dict(і=і, вхід=вх,
        гілки=[dict(схема=г["схема"], зразки=г.get("зразки"), реалізована=г.get("реалізована", True)) for г in е["гілки"]],
        пакет=[dict(схема=г["схема"], базова=((г.get("спец") or {}).get("мисматч") or {}).get("базова", г["схема"]),
                    поєднання=(г.get("спец") or {}).get("палітра_практична", {}).get("поєднання"),
                    бриф=П.для_пакета(г["спец"]["палітра_практична"]) if г.get("спец") else None) for г in г_п]))
    if і % 50 == 0: print(і, flush=True)
pathlib.Path(sys.argv[2]).write_bytes(gzip.compress(json.dumps(out, ensure_ascii=False).encode()))
print("готово", len(out))
