/* Незалежні прицільні проби PR #1974. Аргумент — дерево перевіреної голови. */
const fs = require('fs'), path = require('path'), assert = require('assert/strict');
const корінь = path.resolve(process.argv[2]);
const файл = path.join(корінь, 'аудит/проби/ремонт_шар.js');
const початок = fs.readFileSync(файл, 'utf8').split('(async () => {')[0];
const {міст, середовище, повідомлення, заяви} = new Function('require', '__dirname', 'process',
  початок + '\nreturn {міст, середовище, повідомлення, заяви};')(
    require, path.dirname(файл), {argv: []});
async function main(){
  const факти = {};
  const розмітка = міст({повідомлення: {рядок: повідомлення('схема')}}).розмітка;
  const ключ = розмітка[0].ключ;
  const розбір = текст => міст({розмітка_повідомлень: розмітка, відповідь_моделі: текст});
  const текст = JSON.stringify({[ключ]: 'Розмір шарфа невідомий.'});
  факти.склеєні_обєкти = розбір(текст + текст).заяви[0].стан;
  факти.масив = розбір('[' + текст + ']').заяви[0].стан;
  факти.невірний_тип = розбір(JSON.stringify({[ключ]: ['Речення.']})).заяви[0].стан;
  факти.рамка_markdown = розбір('```json\n' + текст + '\n```').заяви[0].стан;
  факти.чужий_ключ = розбір(JSON.stringify({[ключ]: 'Речення.', зайве: 'Інше.'})).помилки;
  assert.equal(факти.склеєні_обєкти, 'missing_text');
  assert.equal(факти.масив, 'missing_text');
  assert.equal(факти.невірний_тип, 'missing_text');
  assert.equal(факти.рамка_markdown, 'translated');
  assert.equal(факти.чужий_ключ[0].що, 'unknown_key');

  let виклики = 0;
  const порожня = середовище(async () => {виклики++; await Promise.resolve(); return '{}';});
  const картка = () => ({питання: ['а', 'б'].map(і => ({повідомлення: повідомлення(і)}))});
  const перша = картка(), друга = картка();
  await Promise.all([порожня.питаннямиП(перша, 'hand_1'), порожня.питаннямиП(друга, 'hand_2')]);
  факти.спільний_збій = {виклики, стани: [перша, друга].map(к => к.питання.map(п => п.стан_перекладу)),
    тексти: [перша, друга].map(к => к.питання_жінці.length),
    память: [перша, друга].map(к => к.питання_з_пам_яті)};
  assert.equal(виклики, 2);
  assert.deepEqual(факти.спільний_збій.тексти, [2, 2]);
  assert.deepEqual(факти.спільний_збій.память, [0, 0]);
  assert.ok(факти.спільний_збій.стани.flat().every(с => с === 'fallback'));

  const надіслані = [];
  const часткова = середовище(async промпт => {
    const вхід = заяви(промпт); надіслані.push(вхід.map(з => з.key));
    return JSON.stringify(Object.fromEntries(вхід.filter((_, і) => надіслані.length > 1 || і === 0)
      .map(з => [з.key, 'Властивість цього шарфа невідома.'])));
  });
  const результат = await часткова.повідомленнямП({а: повідомлення('а'), б: повідомлення('б')}, 'частково');
  факти.частковий_повтор = {ключів: надіслані.map(к => к.length),
    стани: результат.заяви.map(з => з.стан), тексти: Object.keys(результат.тексти)};
  assert.deepEqual(факти.частковий_повтор.ключів, [2, 1]);
  assert.ok(факти.частковий_повтор.стани.every(с => с === 'translated'));

  const безМоделі = середовище(async () => {throw Error('Не мало бути виклику');});
  require('vm').runInContext('МОДЕЛЬ_МОВИ_П = null', безМоделі);
  const к = картка(); await безМоделі.питаннямиП(к, 'без_моделі');
  факти.без_моделі_текстів = (к.питання_жінці || []).length;
  assert.equal(факти.без_моделі_текстів, 0);
  console.log(JSON.stringify(факти, null, 2));
}
main().catch(е => {console.error(е); process.exitCode = 1;});
