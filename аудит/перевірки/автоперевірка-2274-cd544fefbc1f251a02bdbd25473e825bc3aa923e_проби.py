"""Відтворює пропуски приладу саме з перевіреної голови #2274, без зміни реалізації."""
import ast
import subprocess
import types
from pathlib import Path

ГОЛОВА = "cd544fefbc1f251a02bdbd25473e825bc3aa923e"
КОРІНЬ = Path(__file__).resolve().parents[2]
ПРИЛАД = "джерела/прилади/корінь_річ_колір_вимір.py"


def текст(шлях):
    """Читає файл призначеної голови без переходу на іншу гілку."""
    return subprocess.check_output(
        ["git", "show", f"{ГОЛОВА}:{шлях}"], cwd=КОРІНЬ
    ).decode("utf-8")


def місця(модуль, код, файл="приклад.py"):
    """Повертає позиції, пункти й шляхи обох Python-лічильників на фрагменті."""
    дерево = ast.parse(код)
    батьки = {д: в for в in ast.walk(дерево) for д in ast.iter_child_nodes(в)}
    знайдені = модуль.шлях_А(файл, дерево, батьки) + модуль.шлях_Б(файл, дерево, батьки)
    return sorted((м.рядок, м.пункт, м.шлях) for м in знайдені)


