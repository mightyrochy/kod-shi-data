"""Сегмент 2.12 з тоном нижче невизначеності, виміряний У вікні слова крамниці: що віддає звести_колір і колір_збагачення."""
import os, sys
дж = os.path.abspath(os.path.join(sys.argv[1], "джерела")); os.chdir(дж); sys.path.insert(0, дж)
import жнива_колір as ЖК, фід_збагачення as ФЗ, verify as V, colorspace as CS
for слово, lab in (("чорний", (16.0, 0.6, -1.0)), ("білий", (93.0, 0.3, 1.2)), ("сірий", (55.0, 0.8, -1.5))):
    в = V.ЛЕКСИКОН[слово]; L, C, h = CS.lch(lab)
    сег = dict(слово=слово, частка=0.9, lab=list(lab), hex=CS.hex_з_lab(lab), у_вікні=True, розкид=2.0, плям=0,
               світлота=L, хрома=[round(C, 1), 4.5], тон=None, колір_тип="невідомо")
    осн, _, спір = ЖК.звести_колір([сег], слово, [слово])
    зб = dict(версія=2, колір_основний=dict(слово=осн["слово"], hex=осн.get("hex"), частка=осн["частка"],
              **{к: осн[к] for к in ("колір_тип", "колір_не_вимір") if к in осн}))
    print("%-7s вікно L %.0f–%.0f C %.0f–%.0f · вимір L %.1f C %.1f · тип %s · за_чим «%s» · колір_збагачення lab=%s" % (
        слово, в[0], в[1], в[2], в[3], L, C, осн.get("колір_тип", "—"), осн.get("за_чим"), ФЗ.колір_збагачення(зб)[1]))
