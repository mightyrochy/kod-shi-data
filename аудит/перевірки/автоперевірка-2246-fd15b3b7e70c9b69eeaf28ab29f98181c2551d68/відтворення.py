"""Дві прицільні проби межі опису; аргумент — тека «джерела» перевірюваного дерева."""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(sys.argv[1]).resolve()))
import розбір_відповідей as Р
import дріт_моделі as Д

речі = [
    {"id": "ж-00001@test.example", "слот": "сукня", "тип": "сукня", "код_кольору": "beige"},
    {"id": "ж-00002@test.example", "слот": "взуття", "тип": "лофери", "код_кольору": "black"},
]
відповідь = {"text": "The look works.", "about_items": [{"n": "x1", "text": "A dress."}],
             "named": [{"n": "x1", "what": "dress"}]}
розбір = Р.опис_відповідь_з_json(json.dumps(відповідь), каталог=речі, склад=[р["id"] for р in речі])
повтор = json.loads(розбір["повторний_виклик"])
print("ПОВТОР:", json.dumps(повтор, ensure_ascii=False))
print("Входжень повного id другої речі в повторі:", json.dumps(повтор, ensure_ascii=False).count(речі[1]["id"]))

вхід = {"образ": {"речі": [{"н": "#1·01", "слот": "взуття", "тип": "чоботи", "фото_номери": [1]}]},
        "заміна_запасні": {"річ": "#1·01", "чому": "kind", "запасні": [
            {"н": "#2·01", "слот": "взуття", "тип": "лофери", "код_кольору": "beige", "фото_номери": [2]}]}}
дріт = Д.опис(вхід)
запасна = дріт["swap_spares"]["spares"][0]
print("ЗАПАСНА:", json.dumps(запасна, ensure_ascii=False))
print("Поля виду запасної:", json.dumps({к: запасна[к] for к in ("kind", "type") if к in запасна}))
print("Підпис фото лоферів:", Р.підписи_кадрів(вхід, 2)[1])
