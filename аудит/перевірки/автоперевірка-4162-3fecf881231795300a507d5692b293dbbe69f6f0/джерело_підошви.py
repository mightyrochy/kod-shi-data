import json, pathlib, pickle, sys
sys.path.insert(0, str(pathlib.Path(sys.argv[1]).resolve() / 'джерела'))
import фід_взуття as Ф
import пара_взуття as П

каталог, офери = pickle.loads(pathlib.Path(sys.argv[2]).read_bytes())
сирі = {о['id']: о for о in офери}
вади = []
for р in каталог:
    if р.get('слот') != 'взуття' or not р.get('підошва') or р.get('підошва_коди'):
        continue
    о = сирі[р['id']]
    з_параметрів = Ф.підошва_картки(о.get('параметри'), '')
    if з_параметрів:
        continue
    текст = ' '.join([о.get('назва') or '', о.get('опис') or '']).lower()
    з_тексту = Ф.підошва_картки(None, текст)
    коди, джерело = П.підошва(р)
    вади.append(dict(id=р['id'], підошва_запису=р['підошва'],
        підошва_з_параметрів=з_параметрів, підошва_з_тексту=з_тексту,
        коди_визначення=коди, джерело_визначення=джерело))
вихід = dict(пар=sum(р.get('слот') == 'взуття' for р in каталог),
             текст_названо_карткою=len(вади), випадки=вади)
print(json.dumps(вихід, ensure_ascii=False, indent=2))
assert len(вади) == 25
assert all(в['підошва_з_тексту'] == в['підошва_запису'] and в['джерело_визначення'] == П.КАРТКА for в in вади)
