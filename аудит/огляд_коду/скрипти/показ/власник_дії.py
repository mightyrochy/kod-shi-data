"""Мірило кроку 4.5 (один власник стану дії): верхні змінні показу, які пишуть два й більше модулів, і механізми
версій та скасування — одним лічильником ДО/ПІСЛЯ. Модулі — `джерела/показ/*.js` у порядку підключення з
`показ.html`; розбір — той самий `статика.py` (склеєний файл, межа модуля — його перший рядок).
Запуск з кореня: python3 аудит/огляд_коду/скрипти/показ/власник_дії.py [корінь-копії] [--імена]"""
import json, os, re, subprocess, sys, tempfile
КОРІНЬ = next((а for а in sys.argv[1:] if not а.startswith("--")), ".")
ДЖ = os.path.join(КОРІНЬ, "джерела")
порядок = re.findall(r'<script src="показ/([^"]+)"', open(os.path.join(ДЖ, "показ.html"), encoding="utf-8").read())
частини, межі, р = [], [], 2
for ф in порядок:
    т = open(os.path.join(ДЖ, "показ", ф), encoding="utf-8").read().rstrip("\n") + "\n"
    межі.append((р, ф)); частини.append(т); р += т.count("\n")
with tempfile.NamedTemporaryFile("w", suffix=".html", delete=False, encoding="utf-8") as тф:
    тф.write("<script>\n" + "".join(частини) + "</script>\n")
статика = os.path.join(os.path.dirname(os.path.abspath(__file__)), "статика.py")
ст = json.loads(subprocess.run([sys.executable, статика, тф.name], capture_output=True, text=True, check=True).stdout)
os.unlink(тф.name)
def модуль(рядок):
    м = межі[0][1]
    for п, ф in межі:
        if рядок >= п:
            м = ф
    return м
мф = {ф["ім"]: модуль(ф["з"]) for ф in ст["реєстр"]}
кілька = {}
for ім, г in ст["глобалі"].items():
    м = {мф.get(ф, "верх") for ф in г["пишуть"] + г["мутують"] if ф != "<верх>"}
    if len(м) > 1:
        кілька[ім] = sorted(м)
# Механізми версій і скасування з наряду 4.5 і власник `стан.js`: ознака — оголошення чи поле, що їх тримає.
МЕХАНІЗМИ = [("в.зміна/записана_зміна (картки)", r"записана_зміна"),
             ("ЗАМІНИ_П + застаріло (картки)", r"const ЗАМІНИ_П = new WeakMap|let застаріло = false"),
             ("версія_вердиктів (пакет)", r"'версія_вердиктів'"),
             ("ПОКОЛІННЯ_ЖУРНАЛУ_П (пакет)", r"\bПОКОЛІННЯ_ЖУРНАЛУ_П\b"),
             ("ПОКОЛІННЯ_МОСТА_П (воркер_міст)", r"const ПОКОЛІННЯ_МОСТА_П\b"),
             ("ПОКОЛІННЯ_СЦЕНАРІЮ_П (паспорт)", r"let ПОКОЛІННЯ_СЦЕНАРІЮ_П\b"),
             ("ЧАТ_ЗАПИТ_П (паспорт)", r"let ЧАТ_ЗАПИТ_П\b"),
             ("ХІД_ПЛИТОК_П (випадок/мовний_шар)", r"const ХІД_ПЛИТОК_П\b"),
             ("ПОВІДОМЛЕННЯ_В_ДОРОЗІ_П (мовний_шар)", r"const ПОВІДОМЛЕННЯ_В_ДОРОЗІ_П\b"),
             ("п.номер/п.аборт (оцінка)", r"п\.номер\s*\+=|п\.аборт\s*=\s*new AbortController"),
             ("власник дії ДІЇ_П (стан)", r"const ДІЇ_П\b")]
код = "".join(частини)
є = [н for н, ш in МЕХАНІЗМИ if re.search(ш, код)]
print("модулів %d; верхніх змінних %d; пишуть ≥ 2 модулів: %d" % (len(порядок), len(ст["глобалі"]), len(кілька)))
if "--імена" in sys.argv:
    for ім, м in sorted(кілька.items(), key=lambda кд: (-len(кд[1]), кд[0])):
        print("  %s (%d): %s" % (ім, len(м), ", ".join(м)))
print("механізмів версій і скасування: %d" % len(є))
for н in є:
    print("  " + н)
