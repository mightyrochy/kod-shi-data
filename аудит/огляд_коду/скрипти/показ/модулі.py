"""ДО для кроку 3.4: розклад верхніх функцій `показ.html` за ділянками файла (межі — заголовки розділів `/* ── */`,
зведені за відповідальністю) і зв'язність між ними: виклики через межу ділянки, глобалі, які пишуть з кількох ділянок.
Запуск з кореня: python3 аудит/огляд_коду/скрипти/показ/модулі.py <статика.json>"""
import json, sys
from collections import Counter, defaultdict
ст = json.load(open(sys.argv[1], encoding="utf-8"))
# (перший рядок, ділянка) — за заголовками розділів показ.html на f25c72d
ДІЛЯНКИ = [(2116, "сховище і пакет"), (2406, "картки й вердикти"), (3763, "журнал і звіт власника"),
           (5486, "сценарії"), (5756, "профіль, екрани, аркуш"), (6400, "розмова й паспорт"),
           (8800, "знайомство"), (9035, "старт"), (9318, "клієнт моделі"), (10107, "мовний шар картки"),
           (10675, "розмова через мовну модель"), (11099, "приміряння"), (11743, "Pyodide і міст"),
           (11934, "збір: стадії й відмови"), (12272, "оцінка образу"), (13446, "збір: зібратиОбразиП"),
           (15235, "палітра")]
def ділянка(р):
    д = ДІЛЯНКИ[0][1]
    for п, ім in ДІЛЯНКИ:
        if р >= п:
            д = ім
    return д
дф = {р["ім"]: ділянка(р["з"]) for р in ст["реєстр"]}
рядки = Counter()
for р in ст["реєстр"]:
    рядки[дф[р["ім"]]] += р["рядків"]
дг = {ім: ділянка(г["рядок"]) for ім, г in ст["глобалі"].items()}
межа, усі = Counter(), 0
for ф, імена in ст["граф"].items():
    for і in імена:
        if і in дф:
            усі += 1
            if дф[і] != дф[ф]:
                межа[(дф[ф], дф[і])] += 1
пишуть = {}
for ім, г in ст["глобалі"].items():
    д = {дф.get(ф, "верх") for ф in г["пишуть"] + г["мутують"] if ф != "<верх>"}
    if д:
        пишуть[ім] = д
кілька = {ім: д for ім, д in пишуть.items() if len(д) > 1}
print("ділянка\tфункцій\tрядків\tвиклики назовні\tвиклики ззовні")
for _, ім in ДІЛЯНКИ:
    print("%s\t%d\t%d\t%d\t%d" % (ім, sum(1 for д in дф.values() if д == ім), рядки[ім],
          sum(к for (а, б), к in межа.items() if а == ім), sum(к for (а, б), к in межа.items() if б == ім)))
print("\nребер функція→функція %d, з них через межу ділянки %d (%.0f %%)" % (усі, sum(межа.values()), 100 * sum(межа.values()) / усі))
print("глобалей (let/const) %d; змінюваних із функцій %d; змінюваних із ≥ 2 ділянок %d" % (len(ст["глобалі"]), len(пишуть), len(кілька)))
for ім, д in sorted(кілька.items(), key=lambda кд: -len(кд[1]))[:15]:
    print("  %s: %s" % (ім, ", ".join(sorted(д))))
print("\nнайбільші потоки між ділянками:")
for (а, б), к in межа.most_common(12):
    print("  %s → %s: %d" % (а, б, к))
