"""Верхні функції показу, що не виконались у жодній сцені виміру, з класом за ім'ям і місцем.
Запуск з кореня: python3 аудит/огляд_коду/скрипти/показ/невиконане.py <аналіз.json> > аудит/огляд_коду/показ_невиконане.tsv"""
import json, re, sys
from collections import Counter
д = json.load(open(sys.argv[1], encoding="utf-8"))
КЛАСИ = [  # (клас, шаблон імені) — перший збіг
    ("запасний шлях (виклик 0 / Main, збій, повтор)", r"Main|ПоРозмові|реплікоюП|злитиВідповіді|[Зз]бій|Відмов|стилісткаП$|станДляШі|написиДовідки|записатиВикликРозмови|дочекатисьЧату"),
    ("кілька профілів і збережені сценарії", r"Профіль$|перемкнути|Сценарі|рядокЗПолів|рукаТоркнулась|відкритиАркушПрофілю"),
    ("оцінка: правка переліку з фото", r"Виправлен|Редактор|виправити|пікселіДотику|торкнутисяФото|наповнитиКола|оцінитиРечіЗФото|речіЗФото"),
    ("помада", r"[Пп]омад"),
    ("фото, портрет, файли", r"Портрет|Фото|фото|запакувати|розпакувати|копіювати|картинк|б64|блоб"),
    ("стенд і прилади", r"Стенд|стенд"),
]
рядки, лічба = [], Counter()
for ф in д["невиконані"]:
    if not ф["з"]:
        continue
    кл = next((к for к, ш in КЛАСИ if re.search(ш, ф["ім"])), "інше")
    if not ф["досяжна_статично"]:
        кл = "статично недосяжна"
    лічба[кл] += ф["рядків_джерела"]
    рядки.append((ф["ім"], ф["з"], ф["рядків_джерела"], "так" if ф["досяжна_статично"] else "ні", "так" if ф["стенд"] else "", кл))
print("функція\tрядок\tрядків\tдосяжна_статично\tзгадує_стенд\tклас")
for р in sorted(рядки, key=lambda р: (р[5], -р[2])):
    print("\t".join(map(str, р)))
print("за класами (рядків джерела):", dict(лічба.most_common()), file=sys.stderr)
