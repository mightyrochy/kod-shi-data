"""Ошатність речі: пул (`інтервал_типу`, тип) проти суду (`інтервал_формальності`: тип ∩ модифікатор, бал фото, текстура)
і проти бала фото; текстура речі — коди через дефіс (verify) проти коду розбору (підкреслення). Запуск: cd wt/джерела && python3 p_form.py"""
import json, sys, collections as K; sys.path.insert(0, ".")
import bridge as B, стенд_знімок as СЗ, формальність as Ф, каталог_розбір as КРБ
вх0 = json.load(open("стенд_вх.json", encoding="utf-8"))
B.виклик("запити", json.dumps(dict(вх0, сценарій=dict(СЗ.СЦЕНАРІЇ["офіс·18°C"]), випадок="офіс"), ensure_ascii=False))
кат = B.каталог_останнього_пакета()
Л = K.Counter(); тк = K.Counter()
for r in кат:
    l, h, _ = Ф.інтервал_типу(r.get("тип")); fl, fh = Ф.інтервал_формальності(r); ф = Ф._бал_фото(r)
    Л["усього"] += 1
    if l is None: Л["тип: без інтервалу"] += 1
    if fl is None: Л["суд: без інтервалу"] += 1
    if l is not None and fl is not None:
        Л["обидва"] += 1
        if (float(l), float(h)) != (fl, fh): Л["пул≠суд (інтервал)"] += 1
        if fh < l or fl > h: Л["пул і суд не перетинаються"] += 1
        if abs(fh - h) >= 2 or abs(fl - l) >= 2: Л["край різниться ≥2 щаблі"] += 1
    if ф is not None:
        Л["є бал фото"] += 1
        if l is not None and not (l <= ф <= h): Л["бал фото поза інтервалом типу"] += 1
        if l is not None and (ф < l - 2 or ф > h + 2): Л["бал фото далі ніж 2 щаблі від інтервалу типу"] += 1
    тк[r.get("текстура")] += 1
for k, v in Л.items(): print("  %-48s %6d" % (k, v))
print("текстура в каталозі:", dict(тк.most_common(12)))
print("ключі полярностей:", sorted(Ф.ПОЛЯРНОСТІ_ФОРМАЛЬНОСТІ["текстура"])); print("коди розбору:", КРБ.ТЕКСТУРА)
print("спільних кодів полярностей і розбору:", sorted(set(Ф.ПОЛЯРНОСТІ_ФОРМАЛЬНОСТІ["текстура"]) & set(КРБ.ТЕКСТУРА)))
