"""Підсумкова таблиця кроків: Pyodide (Chromium) / CPython 3.12 на тих самих викликах; частки кроків усередині
викликів — із семплера CPython (cpy_семпл.json), перенесені на час Pyodide того самого типу виклику.
python3 стадії.py <SP>"""
import json, sys, os, statistics as S, collections
SP = sys.argv[1]; П = os.path.join(SP, 'прогони')
j = lambda ф: json.load(open(os.path.join(П, ф), encoding='utf-8'))
мед = lambda xs: S.median(xs)
виклики = sorted(j('виклики_1.json'), key=lambda в: в['w0'])
ч1 = j('часи_1.json'); т0 = ч1['т0']
у_зборі = [i for i, в in enumerate(виклики) if в['w0'] >= т0 - 50 and в['ім'] != 'оцінка']
до_збору = [i for i, в in enumerate(виклики) if в['w0'] < т0 - 50]
оцінка = [i for i, в in enumerate(виклики) if в['ім'] == 'оцінка']
def час(файли, ключ, індекси):
    р = []
    for ф in файли:
        в = ключ(j(ф))
        р.append(sum(в[i]['мс'] for i in індекси))
    return мед(р), р
pyo = ['pyo_%d.json' % i for i in (1, 2, 3)]; cpy = ['cpy_х_%d.json' % i for i in (1, 2, 3)]
кп = lambda д: д['відтворення']['р']['виклики']; кц = lambda д: д['відтворення']['виклики']
def рядок(назва, інд):
    a, ар = час(pyo, кп, інд); b, бр = час(cpy, кц, інд)
    return назва, a, b, ар, бр
табл = []
for назва, інд in [('усі виклики bridge до «Зібрати» (паспорт, палітри, вибір_палітри, мова…)', до_збору),
                   ('«Зібрати образи»: усі виклики bridge', у_зборі), ('«Оціни мій образ» (сцена 6)', оцінка)]:
    табл.append(рядок(назва, інд))
for ім in ['запити', 'від_моделі', 'показ', 'опис', 'мова', 'вибір_палітри', 'палітри']:
    табл.append(рядок('  bridge.' + ім + (' (у зборі)' if ім in ('показ', 'опис', 'мова') else ''),
                      [i for i in (у_зборі if ім in ('показ', 'опис', 'мова') else range(len(виклики))) if виклики[i]['ім'] == ім]))
print('| крок | Pyodide мс (медіана; 3 прогони) | CPython 3.12 мс | Pyodide/CPython |')
print('|---|---|---|---|')
for н, a, b, ар, бр in табл:
    print('| %s | %.0f (%s) | %.0f (%s) | %.2f |' % (н, a, '/'.join('%.0f' % x for x in ар), b, '/'.join('%.0f' % x for x in бр), a / b if b else 0))
# частки кроків усередині типів викликів (семплер CPython)
с = j('cpy_семпл.json')['семпли']; за = с['за_викликом']
вкл = collections.defaultdict(dict)
for к, n in с['вкл_за_іменем']:
    ім, ф = к.split('|', 1); вкл[ф][ім] = n
pyo_ім = collections.defaultdict(list); cpy_ім = collections.defaultdict(list)
for ф in pyo:
    t = collections.Counter()
    for x in кп(j(ф)): t[x['ім']] += x['мс']
    for к, v in t.items(): pyo_ім[к].append(v)
for ф in cpy:
    t = collections.Counter()
    for x in кц(j(ф)): t[x['ім']] += x['мс']
    for к, v in t.items(): cpy_ім[к].append(v)
кроки = [
    ('г) прогрів каталогу: фід_каталог._база_прогону (XML-фід + таблиця), на екрані «Палітра»', 'фід_каталог.py:_база_прогону', 'вибір_палітри'),
    ('   з них розбір XML (фід_розбір.читати_yml_кроками)', 'фід_розбір.py:читати_yml_кроками', 'вибір_палітри'),
    ('   з них відновлення таблиці (таблиця_каталогу.відновити_кроками)', 'таблиця_каталогу.py:відновити_кроками', 'вибір_палітри'),
    ('ґ) пул руки 1 «тінь правил» (міст_запити._пул_руки_1 → _пакет_каталогу)', 'міст_запити.py:_пул_руки_1', 'запити'),
    ('ґ) усі пули в запити (міст_пакет._пакет_каталогу_кроками: тінь р.1 + р.1 + р.2)', 'міст_пакет.py:_пакет_каталогу_кроками', 'запити'),
    ('   з них вкладання пулу в бюджет (_пакет_у_бюджет_кроками)', 'міст_пакет.py:_пакет_у_бюджет_кроками', 'запити'),
    ('   з них прогін фіду (фід_каталог.прогін_кроками)', 'фід_каталог.py:прогін_кроками', 'запити'),
    ('бриф (brief.бриф → hypergraph.простір) у від_моделі ×15', 'brief.py:бриф', 'від_моделі'),
    ('бриф у запити', 'brief.py:бриф', 'запити'),
    ('е) суд образів у від_моделі: _вердикти_образів', 'міст_відповіді.py:_вердикти_образів', 'від_моделі'),
    ('е) суд: перевірити_від_моделі (разом із викликами з _вердикти_образів)', 'суд_від_моделі.py:перевірити_від_моделі', 'від_моделі'),
    ('е) суд образу кодом pipeline.перевірити_образ (66 образів) у від_моделі', 'pipeline.py:перевірити_образ', 'від_моделі'),
    ('   повнота образу (повнота_образу.повнота_набору)', 'повнота_образу.py:повнота_набору', 'від_моделі'),
    ('е) суд «Оціни мій образ» (оцінка_образу.суд_кроками)', 'оцінка_образу.py:суд_кроками', 'оцінка'),
    ('г) прогрів каталогу для оцінки (оцінка_образу.прогріти_каталог_кроками)', 'оцінка_образу.py:прогріти_каталог_кроками', 'оцінка'),
    ('д) вимір кольору з фото (річ_з_фото.виміряти), лише сцена 6', 'річ_з_фото.py:виміряти', 'оцінка'),
    ('показ: фото речей (міст_опис._фото_речі) у опис', 'міст_опис.py:_фото_речі', 'опис'),
]
print('\n| крок (частка з семплера CPython) | частка виклику | Pyodide мс (оцінка за часткою) | CPython мс |')
print('|---|---|---|---|')
for н, ф, ім in кроки:
    ч = вкл.get(ф, {}).get(ім, 0) / за[ім]
    print('| %s | %.0f%% bridge.%s | %.0f | %.0f |' % (н, 100 * ч, ім, ч * мед(pyo_ім[ім]), ч * мед(cpy_ім[ім])))
print('\nвикликів: до збору %d, у зборі %d, оцінка %d' % (len(до_збору), len(у_зборі), len(оцінка)))
