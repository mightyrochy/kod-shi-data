# Мірило картки речі без моделі: тип, слот, набір на всьому каталозі показу.
# python3 -I -B мірило_картки.py <index.html> [<каталог_повний.xml.gz>]   (2-й аргумент — переписування слота писарями)
import sys, os, re, io, gzip, json, base64, zipfile, tempfile, collections
sys.dont_write_bytecode = True
ДЖ = '/home/user/kod-shi-data/джерела'
ІНД = os.path.abspath(sys.argv[1]); СИР = os.path.abspath(sys.argv[2]) if len(sys.argv) > 2 else None
ТМП = tempfile.mkdtemp(dir=os.path.dirname(os.path.abspath(__file__)), prefix='вантаж_')
z = zipfile.ZipFile(io.BytesIO(base64.b64decode(re.search(r'const МОДУЛІ_ПОКАЗУ = "([A-Za-z0-9+/=]+)"', open(ІНД, encoding='utf-8').read()).group(1))))
for ім in ('каталог_таблиця.json.gz', 'каталог_brief.xml'): z.extract(ім, ТМП)
sys.path.insert(0, ДЖ); os.chdir(ТМП)
import таблиця_каталогу as ТК, фід_розбір as ФР, внутрішня_мова as В, фід_слот as ФС
C = collections.Counter
т = json.load(gzip.open('каталог_таблиця.json.gz', 'rt', encoding='utf-8'))
офери = ФР.офери_фіду('каталог_brief.xml'); Б = ТК.відновити(т, офери)['каталог']
н = lambda r: str(r.get('назва_показу') or r.get('назва') or '').lower()
ПРИК = {'прикраси', 'сережки', 'кольє', 'намисто', 'брошка', 'браслет', 'каблучка'}
def слот_типу(тп):
    к = В.код('item_type', тп); return В.ключ('slot', В.СЛОТ_ТИПУ.get(к)) if к else None
def домовленість(с, ст):   # блейзер/кардиган/жилет у верх|верхній_шар; прикраси з підслотом; аксесуар волосся у прикрасах
    return {с, ст} == {'верх', 'верхній_шар'} or (ст == 'прикраси' and с in ПРИК) or (ст == 'головний_убір' and с == 'прикраси')
конф = [r for r in Б if r.get('тип') and слот_типу(r['тип']) not in (None, r['слот']) and not домовленість(r['слот'], слот_типу(r['тип']))]
ОДЯГ = re.compile(r'сукн|плать|платт|сарафан|легінс|леггін|леггинс|лосин|штан|брюк|спідниц|джинси\b|кімоно|кардиган|пальт|жакет|піджак|блуз|сорочк|комбінезон|\bтоп\b|корсет|бандо|халат|туні|светр|джемпер|худі|шорт')
ПОЯС = re.compile(r'пояс|пасок|паск|ремін|ремен')
def одяг_перший(с):
    о, п = ОДЯГ.search(с), ПОЯС.search(с); return bool(о and (not п or о.start() < п.start()))
НАБ = re.compile(r'^(?:\S+\s+){0,2}(костюм|комплект|двійк\w*|трійк\w*|сет|набір)\b')
ВЕРХ = r'(майк|топ|футболк|сорочк|блуз|жилет|піджак|жакет|кардиган|туні|світшот|худі)\w*'; НИЗ = r'(штан|брюк|спідниц|шорт|бермуд|джинс(?:и|ами)\b|легінс|лосин)\w*'
ПАРА = re.compile(r'\b%s\s+(?:з|зі|із|та|і|й|\+)\s+(?:\S+\s+)?%s|\b%s\s+(?:з|зі|із|та|і|й|\+)\s+(?:\S+\s+)?%s' % (ВЕРХ, НИЗ, НИЗ, ВЕРХ))
навпіл = [r for r in Б if r['слот'] in ('верх', 'низ', 'сукня', 'верхній_шар') and (НАБ.search(н(r)) or ПАРА.search(н(r))) and 'костюмн' not in н(r)]
УТОЧ = {('куртка', х) for х in ('пуховик', 'бомбер', 'парка', 'вітровка', 'дублянка', 'шуба', 'анорак')} | {('пальто', х) for х in ('шуба', 'пуховик', 'дублянка')} | {('тренч', 'плащ')}
тв = [r for r in Б if r.get('тип_верхнього') and r.get('тип') and r['тип_верхнього'] != r['тип']]
тв_різні = [r for r in тв if (r['тип'], r['тип_верхнього']) not in УТОЧ and r['тип'] not in ('комплект', 'костюм', 'костюм_повсякденний')]
print('М0 товарів у базі', len(Б), '| оферів почищеного фіду', len(офери))
print('М1 без типу', sum(1 for r in Б if not r.get('тип')))
print('М2 слот ≠ слот свого типу (СЛОТ_ТИПУ, поза домовленостями)', len(конф), C((r['тип'], r['слот']) for r in конф).most_common(6))
print('М3 одяг у «пояс» (іменник одягу раніше за пояс)', sum(1 for r in Б if r['слот'] == 'пояс' and одяг_перший(н(r))),
      '| з них сукні', sum(1 for r in Б if r['слот'] == 'пояс' and одяг_перший(н(r)) and re.search(r'сукн|плать|платт|сарафан', н(r))),
      '| легінси/лосини', sum(1 for r in Б if r['слот'] == 'пояс' and одяг_перший(н(r)) and re.search(r'легінс|леггін|леггинс|лосин', н(r))))
print('М4 у «пояс» тип іншого слота', sum(1 for r in Б if r['слот'] == 'пояс' and r.get('тип') and слот_типу(r['тип']) not in (None, 'пояс')))
print('М5 набори навпіл (набірний іменник на початку або пара верх+низ, слот одягу)', len(навпіл), C(r['слот'] for r in навпіл).most_common())
if os.environ.get('SHOW'):
    for r in навпіл: print('   М5', r['id'], r['слот'], r.get('тип'), '|', н(r)[:70])
    for r in Б:
        if r['слот'] == 'пояс' and одяг_перший(н(r)): print('   М3', r['id'], r.get('тип'), '|', н(r)[:70])
print('М6 тип_верхнього ≠ тип', len(тв), '| різні речі (не уточнення, не частина набору)', len(тв_різні))
print('М7 «мокас…» з іншим типом', sum(1 for r in Б if re.match(r'мокас', н(r)) and r.get('тип') != 'мокасини'))
if СИР:
    if СИР.endswith('.gz'):
        open('сирий.xml', 'wb').write(gzip.open(СИР).read()); СИР = os.path.abspath('сирий.xml')
    сирі = {o['id']: o for o in ФР.офери_фіду(СИР)}
    чисті = {o['id']: o for o in офери}
    def лист(o):
        к = (o.get('категорія') or '').lower().rsplit(' / ', 1)[-1].strip()
        к = к if к in ФС.ІМЕНА_СЛОТІВ else ((o.get('параметри') or {}).get('слот') or '').strip().lower() or к
        return 'прикраси' if к in ПРИК else к
    тр = [(лист(сирі[r['id']]), лист(чисті[r['id']]), 'прикраси' if r['слот'] in ПРИК else r['слот']) for r in Б if r['id'] in сирі]
    print('М8 писарі слота: чистка переписала', sum(a != b for a, b, c in тр), '| фід переписав', sum(b != c for a, b, c in тр),
          '| обидва', sum(a != b != c for a, b, c in тр), '| фід повернув сирий', sum(a != b and c == a for a, b, c in тр))
