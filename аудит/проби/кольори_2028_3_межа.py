"""Перебирає джерело 13 відсутніх насичених тріад і перевіряє запасний показ.

python аудит/проби/кольори_2028_3_межа.py <тека-доказів>
Область доказу — всі дискретні фішки й усі кандидати чинного семплера
джерела. Це не твердження про неможливість тріади в неперервному sRGB.
"""
import copy
import gzip
import inspect
import itertools
import json
import pathlib
import sys
from collections import Counter

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРІНЬ / 'джерела'))
import bridge as М
import palettes as П
import колір_річ as КР
import колір_відношення as КВ


def пари_законні(трійка):
    """Звіряє всі три пари за кінцевими кольорами чинним предикатом."""
    return all(КР.та_сама_сім_я(а, б) == 'ні' and
               КВ.сила(КР.запис_кольору(а), КР.запис_кольору(б), 'triadic')[0] >= 0.5
               for а, б in itertools.combinations(трійка, 2))


def ролі_законні(трійка):
    """Перебирає шість призначень ролей у тріаді з чинним допуском дуг."""
    for а, б, в in itertools.permutations(трійка):
        дуги = П.СХЕМИ['тріада']['тон'](а['h'])
        if (КВ.сила_точки_в_дузі(б['C'], б['h'], дуги['секундант']) >= КВ.КІНЕЦЬ_ЗГАСАННЯ and
                КВ.сила_точки_в_дузі(в['C'], в['h'], дуги['акцент']) >= КВ.КІНЕЦЬ_ЗГАСАННЯ):
            return True
    return False


def головна():
    """Зберігає весь скінченний перебір і відсутність порожнього запасного зразка."""
    вихід = pathlib.Path(sys.argv[1]).resolve()
    вихід.mkdir(parents=True, exist_ok=True)
    старі = json.loads((КОРІНЬ / 'аудит/перевірка/доробка_2028_2/гами-ПІСЛЯ.json').read_text(encoding='utf-8'))
    номери = next(г['без_тріади'] for г in старі if г['гама'] == 'насичені')
    assert len(номери) == 13
    архів = json.loads(gzip.decompress((КОРІНЬ / 'аудит/перевірка/кольори_9858/персони.json.gz').read_bytes()))
    текст, перший = inspect.getsourcelines(П.трійка_з_вікон_схеми)
    рядок = перший + next(і for і, р in enumerate(текст) if 'if len(трійка) != len(РОЛІ)' in р)
    записи = []
    for і in номери:
        вхід = dict(архів[і]['вхід'], вибір_кольору=dict(насиченість='насичені'))
        F = М._features(вхід)[0]
        контраст = П.контраст_особи(F).get('рівень')
        пал = П.палітра_практична(F, самозвіт=вхід.get('самозвіт'), контраст_рівень=контраст, насиченість='насичені')
        assert not any(п['прийом'] == 'тріада' for п in пал['поєднання']), (і, 'тріада вже наявна')
        кольори = [П.кінцевий_колір(к) for к in пал['кольори'] if к['роль'] == 'колір']
        дискретні, згенеровані = Counter(), []
        for т in itertools.combinations(кольори, 3):
            if not П.набір_законний(т, контраст)[0]:
                дискретні['набір'] += 1
            elif not пари_законні(т):
                дискретні['пари'] += 1
            elif not ролі_законні(т):
                дискретні['дуги'] += 1
            else:
                raise AssertionError((і, 'знайдено законну дискретну тріаду', т))
        def стежити(кадр, подія, _аргумент):
            """Фіксує кожного кандидата реального семплера перед його судом."""
            if (кадр.f_code is П.трійка_з_вікон_схеми.__code__ and подія == 'line' and кадр.f_lineno == рядок):
                згенеровані.append(copy.deepcopy(кадр.f_locals['трійка']))
            return стежити
        sys.settrace(стежити)
        try:
            результат = П.трійка_з_вікон_схеми(пал, 'тріада', контраст, П.НАСИЧЕНІСТЬ['насичені'])
        finally:
            sys.settrace(None)
        assert результат is None
        причини = Counter()
        for т in згенеровані:
            if len(т) != 3:
                причини['вікно_хроми_порожнє'] += 1
            elif not П.набір_законний(т, контраст)[0]:
                причини['набір'] += 1
            elif not пари_законні(т):
                причини['пари'] += 1
            else:
                raise AssertionError((і, 'семплер відкинув законну тріаду', т))
        екран = json.loads(М.палітри(вхід))
        г = next(г for г in екран['гілки'] if г['схема'] == 'тріада')
        запасний = next(п for п in пал['поєднання'] if п['прийом'] == г['запасний_прийом'])
        assert len(г['зразки']) == 3 and г['зразки'] == [к['hex'] for к in запасний['кольори']]
        assert all(г['зразки'] for г in екран['гілки'] if г['реалізована'])
        записи.append(dict(персона=і, вхід=вхід, контраст=контраст, кольори=кольори,
                           дискретних=sum(дискретні.values()), відсів_дискретних=dict(дискретні),
                           згенерованих=len(згенеровані), відсів_генерації=dict(причини),
                           кандидати_семплера=згенеровані, запасний_прийом=г['запасний_прийом'],
                           зразки=г['зразки'], екран=екран))
        print(json.dumps({к: з for к, з in записи[-1].items() if к not in ('кольори', 'кандидати_семплера', 'екран', 'вхід')}, ensure_ascii=False), flush=True)
    (вихід / 'межа.json.gz').write_bytes(gzip.compress(json.dumps(записи, ensure_ascii=False).encode(), mtime=0))
    (вихід / 'межа-вимір.json').write_text(json.dumps(dict(персон=len(записи), законних_тріад=0,
        дискретних=sum(р['дискретних'] for р in записи), згенерованих=sum(р['згенерованих'] for р in записи),
        запасний_без_порожніх=13), ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    return 0


if __name__ == '__main__':
    sys.exit(головна())
