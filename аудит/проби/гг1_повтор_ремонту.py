def _відібрати(р):
    try:
        вх = вхід_мосту(р["спільне"], р["ключ"]); текст = відповідь_складання(р["складання"])
        р1 = промпт_ремонту(вх, текст, True)
        пр = р1.get("промпт_ремонту") or ""
        if len(р1.get("образи") or []) < 2 or not пр:
            return dict(збій="нема промпту ремонту")
        keep = sum(len(о.get("keep") or []) for о in json.loads(пр).get("verdict") or [])
        до = опори(р1)
        з = ["образів у ремонт %d з %d записаних" % (len(р1["образи"]), len(р["складання"]["образи"]))]
        if р1.get("нема_в_каталозі"):
            з.append("нема в чинному каталозі: %s" % ", ".join(р1["нема_в_каталозі"][:6]))
        if keep != sum(len(оо) for _, оо in до):
            з.append("keep %d ≠ опор вердикта %d" % (keep, sum(len(оо) for _, оо in до)))
        return dict(вх=вх, текст=текст, до=до, символів=len(пр), зауваження="; ".join(з))
    except Exception as е:
        return dict(збій="%s: %s" % (type(е).__name__, str(е)[:80]))


