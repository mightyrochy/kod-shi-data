    міст("від_моделі", dict(ВХ0, ід=[]))            # каталог і кеші — до розгалуження, спільні дочірнім процесам
    with МП.get_context("fork").Pool(процесів) as пул:
        вих = list(пул.imap(_відібрати, рядки, chunksize=4))
    Л = K.Counter(); за_правилом = K.Counter(); вибрані = []
