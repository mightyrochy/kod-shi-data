def пережила(z, ід, після):
    return any(ключ_опори(x) == ключ_опори(z) and речі_опори(x) & речі_опори(z) for _, оо in після for x in оо)


def лічба(записи):
    """Парна таблиця опор вхідних образів (з ГГ-1 × без) і частки на бік."""
    Л = K.Counter(); за_правилом = K.defaultdict(K.Counter)
    for з in записи:
        а, б = з["з_гг1"], з["без_гг1"]
        for бк, х in (("з ГГ-1", а), ("без ГГ-1", б)):
            if х.get("збій"):
                Л["збій · " + бк + " · " + х["збій"]] += 1
        if а.get("збій") or б.get("збій"):
            Л["входів зі збоєм (пара не лічиться)"] += 1; continue
        Л["входів у лічбі"] += 1
        for ід, оо in а["до"]:
            for z in оо:
                ж = (пережила(z, ід, а["після"]), пережила(z, ід, б["після"]))
                к = {(True, True): "в обох", (True, False): "лише з ГГ-1", (False, True): "лише без", (False, False): "в жодному"}[ж]
                Л["опор"] += 1; Л[к] += 1; за_правилом[z.get("правило")][к] += 1
                Л["з ГГ-1: пережили"] += ж[0]; Л["без ГГ-1: пережили"] += ж[1]
    return Л, за_правилом


