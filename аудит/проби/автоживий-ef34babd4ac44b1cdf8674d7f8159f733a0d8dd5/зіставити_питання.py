"""Таблиця відповідей на кожне питання наряду із записаних фактів та оцінки меж доказу."""
from pathlib import Path
import json

ТЕКА = Path(__file__).resolve().parent
план = json.loads(next(x for x in (ТЕКА / 'НАРЯД.md').read_text(encoding='utf-8').splitlines()
                       if x.startswith('{"since":')))
дані = json.loads((ТЕКА / 'ДОКАЗИ_ПИТАНЬ.json').read_text(encoding='utf-8'))
відповіді = {}


def додати(сцена, pr, стан, факт):
    відповіді[сцена, pr] = (стан, факт)


пори = {
    'ж2_побачення_вечір': 'evening / вечір; поле картки «ввечері»',
    'ж3_співбесіда': 'morning / ранок; поле картки «вранці»',
    'ж7_вечеря_сьомій': 'evening; картка «Ввечері»',
    'ж7_театр_дата': 'evening; картка «Ввечері»; число 19 з дати годиною не стало',
    'ж3_свято_др': 'evening / вечір; поле картки «ввечері»',
    'ж3_кафе_13': 'day; картка «Вдень»',
    'ж3_кафе_20': 'evening; картка «Ввечері»'}
з_годинником = {'ж2_побачення_вечір', 'ж3_кафе_13', 'ж3_кафе_20'}
for сцена, пора in пори.items():
    for п in план['scenes'][сцена]:
        pr = п['pr']
        if pr == 2609:
            додати(сцена, pr, 'Частково', пора + '. Числової години немає; давня частина питання '
                '«поруч із годиною» цим записом не виконується. Пізніші питання цього плану вимагають часу без годинника.')
        elif pr in [2630, 2632, 2628]:
            додати(сцена, pr, 'Частково' if сцена in з_годинником else 'Підтверджено для часу',
                пора + '. Числових полів години/хвилини немає, цитати її слів збережені. ' +
                ('Репліка містить числовий годинник: 12025, вимога його повної відсутності не виконана.'
                 if сцена in з_годинником else 'Числового годинника в перевіреному полі картки немає.'))
        elif pr == 2629:
            if сцена == 'ж3_співбесіда':
                стан, факт = 'Підтверджено для часу', 'Дні обох рук morning, daylight; числового start_hour немає.'
            elif сцена == 'ж7_театр_дата':
                стан, факт = 'Підтверджено для часу', 'Пора evening; 19 з дати годиною не стало; режим розмови.'
            elif сцена == 'ж3_свято_др':
                стан, факт = 'Частково', 'Паспорт evening, день руки 1 artificial; суд/день руки 2 відсутній.'
            elif сцена in ['ж3_кафе_13', 'ж3_кафе_20']:
                стан, факт = 'Частково', 'Пори day/evening, ошатність обох [5,6]. У репліках лишилися 13:00/20:00; образи не збиралися.'
            else:
                стан, факт = 'Частково', 'Дні evening, artificial; числових полів часу немає. Порівняльної оцінки доречності живою людиною немає.'
            додати(сцена, pr, стан, факт)
        elif pr == 2631:
            додати(сцена, pr, 'Частково', 'Пора evening, artificial; у днях рук немає числової години. '
                'Вечірня смуга вийшла formal; порівняльної оцінки доречності образу живою людиною немає.')

додати('ж8_ділова_мороз', 2617, 'Підтверджено у записі',
    'Ремонт о7 повернув верхній_шар ж-04759@feelyou.com.ua, complete=yes; кінцевих карток «ремонт без образів» немає. Видиме фото руки 1 — 5/6.')
додати('ж1_робота', 2617, 'Не доведено повністю',
    'MODEL_VYBIR=assess; кінцеві руки 1–2 повні, блокерів немає. Точний склад сукня + піджак без додаткового верху не трапився.')
додати('ж4_робота_стримано', 2617, 'Частково; rc=2',
    'Заміна руки 1 зберегла слот верхній_шар та інші картки; 4 звірки зелені. Заміна руки 2 — таймаут 120000 мс, завершення не доведене; повтору немає.')
for сцена in ['ж2_побачення_вечір', 'ж2_побачення_день']:
    додати(сцена, 2667, 'Не підтверджено',
        'База вдень [5,6], увечері [7,7], отже не однакова. Вечірній підйом smart → formal замість neat → smart; 12353.')
додати('ж2_побачення_день', 2682, 'Частково',
    'Дні й пакет стилістки neat, daylight; вечірнього підйому немає. Ліміт однієї відкритої зони окремим виміром не доведений.')
додати('ж2_побачення_вечір', 2682, 'Не підтверджено повністю',
    'У пакеті верхнього шару formal, не очікуване smart; K-KOH-10 допускає 2 зони. Умова вечірнього підйому базового neat у записі не трапилась; окремий випадок 12189 не доведено.')
for сцена in ['ж3_кафе_13', 'ж3_кафе_20']:
    додати(сцена, 2667, 'Підтверджено базу', 'Базова ошатність обох кафе [5,6], пори day/evening; режим розмови.')
додати('ж3_кафе_20', 2682, 'Підтверджено базу', 'У розмовній парі кафе вдень/увечері однакова база [5,6]; код збирання за цим режимом не проходився.')
додати('ж3_ювілей_день', 2667, 'Не підтверджено',
    'На запит о 14:00 модель уже в першій відповіді дала evening; кінцеві паспорт і пакет formal, не smart. Ліміт однієї зони для правильного дня не перевірений.')
for pr in [2667, 2682]:
    додати('ж3_ювілей_вечір', pr, 'Не доведено потрібний перехід',
        'Вечір і formal підтверджені; K-KOH-10 — 2 зони. База вже formal, як у денній сцені; smart → formal не трапився.')

# Відповіді сцен, які ще записувалися під час підготовки таблиці, дописуються після їхнього результату.

рядки = ['# Відповіді на питання плану', '',
    'Одна пара «сцена + PR» — одне питання; повний текст кожного питання збережений дослівно в `НАРЯД.md`. '
    'Це оцінка фактів автоматичного прогону та меж доказу; оцінки образів живою людиною немає. '
    '«Не доведено» не означає встановленої причини.', '']
кількість = 0
бракує = []
for сцена, питання in план['scenes'].items():
    рядки += ['## ' + сцена, '', '| PR | Результат питання | Факт / межа доказу |', '|---|---|---|']
    for п in питання:
        кількість += 1
        ключ = (сцена, п['pr'])
        if ключ not in відповіді:
            бракує.append(ключ)
        стан, факт = відповіді.get(ключ, ('Очікує оцінки запису', 'Результат ще не оцінений.'))
        рядки.append(f'| #{п["pr"]} | {стан} | {факт} |')
    рядки += ['', 'Докази: `' + сцена + '/лог.txt`, `' + сцена + '/знімки/доказ.json`, '
               '`ДОКАЗИ_ПИТАНЬ.json`; докладні обмеження — `ЗВІТ.md`.', '']
рядки += [f'Усього питань: {кількість}; без оцінки: {len(бракує)}.', '']
(ТЕКА / 'ПИТАННЯ.md').write_text('\n'.join(рядки), encoding='utf-8')
print(f'Питань {кількість}; без оцінки {len(бракує)}: {бракує}')
