"""Додає докази до наявних рядків, зберігаючи їхній стан і попередні записи."""
from pathlib import Path
import re

ТЕКА = Path(__file__).resolve().parent
РЕПО = ТЕКА.parents[2]
гілка = 'gemini/' + ТЕКА.name
доказ = 'аудит/проби/' + ТЕКА.name
нотатки = {
    12025: 'Побачення ввечері знову показує «Записала: побачення в ресторані о 19:30»; '
           'кафе — «…о 13:00 · кафе · о 13:00» та «…о 20:00 · о 20:00». '
           'Поля часу карток уже «ввечері»/«вдень», числова година відсутня; '
           'цитати й репліка — окремий вимір.',
    12353: 'У парі побачень денна база [5,6], вечірня [7,7]; '
           'вечірній слід K-KOH-06 smart → formal. Однакової бази та очікуваного neat → smart '
           'цим прогоном не отримано.',
    11254: 'У денному побаченні hand_1.code_unknowns має not_json_object, '
           'повтор — texts_missing; вхідні card_unchecked лишились без української відповіді. '
           'Повний список червоних збережений, причина цією сесією не встановлена.',
    11600: 'FOTO=1: у морозі видимих фото руки 1 — 5 з 6, руки 2 — 6 з 6; '
           'у стриманій роботі руки 1 — 5 з 6. Це вимір видимих картинок, '
           'окремий від доставки кадрів до моделі. FOTO=0 інших сцен не є перевіркою фото.'}
рядки = (РЕПО / 'аудит/БЕКЛОГ.md').read_text(encoding='utf-8').splitlines()
вихід = ['# Нові докази наявних відкритих проблем; стани збережено.']
for номер, текст in нотатки.items():
    рядок = next(р for р in рядки if re.match(r'^\|\s*' + str(номер) + r'\s*\|', р))
    стан = re.split(r'(?<!\\)\|', рядок)[4].strip()
    assert not стан.startswith('**ЗАКРИТО'), номер
    вихід.append(f'стан {номер}: {стан} · 03.11.2026 UTC: {текст} '
                  f'Доказ: `{доказ}/ДОКАЗИ_ПИТАНЬ.json`, `{доказ}/ЗВІТ.md`; '
                  'виявлено: живий; внесено: давнє')
файл = РЕПО / 'аудит/дошка' / (гілка + '.md')
файл.parent.mkdir(parents=True, exist_ok=True)
файл.write_text('\n'.join(вихід) + '\n', encoding='utf-8')
print('Доповнено рядки: ' + ', '.join(map(str, нотатки)))
