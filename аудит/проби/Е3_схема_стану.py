"""Стан палітри (`вибір_палітри.стан_для_показу`) і промпт мовного шару до нього — ДО і ПІСЛЯ одного писача `scheme`.

Запуск (модель і платні API не викликаються):
    python3 -I аудит/проби/Е3_схема_стану.py <корінь дерева>
Перебирає її схему (нема, кожна з шести схем таблиці й «контраст-мисматч», за іменем і за гілкою), схему стилістки
(нема й кожна) і ноту стилістки; друкує JSON: кожен випадок — заяви `пал-стан`/`пал-нота`/`рідша.N` і рядки
«КОДИ У ЗНАЧЕННЯХ» промпту мовного шару. Два запуски порівнюють побайтно.
"""
import json, os, sys, warnings
from pathlib import Path


def головна():
    """Усі випадки стану палітри одного дерева → JSON у stdout."""
    os.chdir(Path(sys.argv[1]).resolve() / "джерела")
    sys.path.insert(0, str(Path.cwd()))
    warnings.simplefilter("ignore")
    import внутрішня_мова as В, вибір_палітри as П, мовний_шар as М, палітра_схеми as С
    схеми = list(С.СХЕМИ) + [С.МИСМАТЧ]
    гілки = [dict(і=і, схема=сх, вага="ядро" if і < 3 else "statement", рідший=і >= 3,
                  нота_кодами=В.повідомлення("palette_scheme_note", В.заява("scheme_tonal")))
             for і, сх in enumerate(схеми)]
    випадки = []
    for її in [{}] + [{"схема": с} for с in схеми] + [{"гілка": г["і"]} for г in гілки]:
        for стил_схема in [None] + схеми:
            for з_нотою in (False, True):
                стил = {} if стил_схема is None else dict(
                    вибір=dict(схема=стил_схема, гама="насичені", вибір_кольору={"база": "бузковий"},
                               обрала=dict(base="stylist", scheme="stylist", saturation="stylist")))
                if з_нотою and стил:
                    стил["повідомлення"] = В.повідомлення("palette_stylist_choice", *[
                        В.заява("palette_choice_part", part=ч, choice="stylist", source="model", value=None)
                        for ч in ("base", "scheme", "saturation")])
                вих = П.стан_для_показу(dict(її=dict(її, вибір_кольору={"насиченість": "приглушені"}),
                                             стилістка=стил, гілки=гілки, радить=3))
                коди = М._коди_словником(вих["пал-стан"]["statements"])
                випадки.append(dict(її=її, стилістка=стил_схема, нота=з_нотою, стан=вих, коди_у_значеннях=коди))
    print(json.dumps(випадки, ensure_ascii=False, sort_keys=True, indent=0))
    return 0


if __name__ == "__main__":
    sys.exit(головна())
