"""Повтор записаних відповідей 07.11: усі записи й картки її речей, без мережі й викликів моделі."""
import json
from pathlib import Path
import sys

КОРІНЬ = Path(__file__).resolve().parents[3]
sys.path[:0] = [str(КОРІНЬ / 'джерела'), str(КОРІНЬ / 'джерела/прилади')]
import річ_запис_її_річ as Я
import мовний_шар as М
import річ_з_фото as РФ


def main():
    """Виводить назви й сталі ідентифікатори всіх її речей у корпусі приладу."""
    файли = Я.входи(КОРІНЬ)
    Я.звірити(КОРІНЬ, файли)
    вих = []
    for шлях, вид in файли:
        прочитане = Я.прочитати(КОРІНЬ, шлях)
        if прочитане:
            речі, картки = Я.прогнати(*прочитане, вид, (М, РФ))
            if речі or картки:
                вих.append(dict(вхід=шлях, речі=речі, картки=картки))
    текст = json.dumps(dict(входів=len(файли), записи=вих), ensure_ascii=False, indent=1) + '\n'
    if len(sys.argv) > 1:
        Path(sys.argv[1]).write_text(текст, encoding='utf-8')
    else:
        print(текст, end='')


if __name__ == '__main__':
    main()
