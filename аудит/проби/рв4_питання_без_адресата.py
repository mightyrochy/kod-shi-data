"""РВ-4 · п'ять нових записів БЕЗ_ВХОДУ (Н-V13-027): де вони опиняються на живому шляху.

С-54 назвала ціну: «п'ять зайвих рядків у кожному пакеті для моделі». Тут
міряється, куди ці п'ять рядків ідуть насправді: (1) показ бере ПЕРШІ П'ЯТЬ
`в.питання` у діагноз екрана і в журнал вердикту (`питання_коду`, показ.html
`однаРука`); (2) чи хоч одне з них є в промптах моделі й у вердикті для неї.
Запуск із теки `джерела`: python3 ../аудит/проби/рв4_питання_без_адресата.py
"""
import json
import re
import sys

sys.path.insert(0, ".")
import bridge as B  # noqa: E402

НОВІ = ("K-EYE-01", "K-WCH-01", "K-GLV-01", "K-HAT-01", "K-ACC-04")
вх = json.load(open("стенд_вх.json"))
вх.update(каталог="каталог_brief.xml", без_фото=1, варіантів=3)
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
пул = json.loads(r["B"])["пул"]
def суд(слоти):
    ядро = [пул[с][0]["н"] for с in слоти if пул.get(с)]
    відп = json.dumps(dict(версія="1", образи=[dict(ід="о1", підпис="проба РВ-4", речі=ядро)]),
                      ensure_ascii=False)
    return ядро, json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=відп), ensure_ascii=False)))


ядро, вм = суд(("сукня", "взуття", "сумка", "головний_убір"))
пит = вм.get("питання") or []
print("образ: %s · питань у виході від_моделі: %d (стеля bridge — 12)" % (", ".join(ядро), len(пит)))
for і, z in enumerate(пит, 1):
    print("  %2d. %-9s %s%s" % (і, z.get("правило"), str(z.get("суть"))[:70],
                                "   ← Н-V13-027" if z.get("правило") in НОВІ else ""))
топ5 = [z.get("правило") for z in пит[:5]]
print("\nперші п'ять — саме їх показ кладе в діагноз екрана і в `питання_коду` журналу:", топ5)
print("  з них записів БЕЗ_ВХОДУ (черга на вхід, від речей не залежить): %d із 5"
      % sum(1 for z in пит[:5] if str(z.get("сила_нп_джерело") or z.get("джерело") or "")
            .startswith("без входу") or z.get("правило") in НОВІ))
print("  питань про РЕЧІ ЦЬОГО образу, які туди не влізли:",
      [z.get("правило") for z in пит[5:] if z.get("правило") not in НОВІ
       and not str(z.get("сила_нп_джерело") or "").startswith("без входу")])
# ── ТОЙ САМИЙ СУД НА ПОВНІШОМУ ОБРАЗІ: чи переживають стелю 12 єдині питання ДО ЖІНКИ ──
ядро2, вм2 = суд(("сукня", "верх", "взуття", "сумка", "головний_убір", "пояс", "прикраси", "шарф"))
пит2 = [z.get("правило") for z in (вм2.get("питання") or [])]
print("\nповніший образ (%d речей): питань %d · K-SHO-13 у списку: %s · K-HAT-01 у списку: %s · перші п'ять: %s"
      % (len(ядро2), len(пит2), "K-SHO-13" in пит2, "K-HAT-01" in пит2, пит2[:5]))
слова = ("окуляр", "годинник", "рукавич", "ремен", "обхват голови", "міжзіниц")
for назва in ("промпт_ремонту", "промпт_вибору", "промпт_лише_вибору"):
    т = str(вм.get(назва) or "")
    print("%-19s %6d символів · згадок п'яти воріт: %s"
          % (назва, len(т), {w: len(re.findall(w, т)) for w in слова if re.search(w, т)} or "жодної"))
в = json.dumps(вм.get("вердикт") or {}, ensure_ascii=False)
print("%-19s %6d символів · згадок п'яти воріт: %s"
      % ("вердикт (для моделі)", len(в), {w: len(re.findall(w, в)) for w in слова if re.search(w, в)} or "жодної"))
