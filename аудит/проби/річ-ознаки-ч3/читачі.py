"""Вимірює читачів на записаних профілях без викликів моделі."""
import json, pathlib, sys

К = pathlib.Path(__file__).resolve().parents[3]
sys.path.insert(0, str(К / "джерела"))
import brief as Б, bases as Р, міст_вхід as М, palette as П, суд_чеклісти as С


def main():
    """Друкує факт утримання оцінок та контроль фізичного джерела і її відповіді."""
    вих = []
    for шлях in sorted((К / "аудит/проби/жінки").glob("*.json")):
        ж = json.loads(шлях.read_text("utf8"))
        for дж in ("model_hex", "spectro"):
            F = М.features(dict(шкіра=ж["skin"], волосся=ж["hair"], очі=ж["eyes"], source=дж))[0]
            бік = П.бік_b_проти_людини(F)
            входи = С.входи_палітри(F, дж)
            ранг, пояснення = Р.ранг(F, {"а": ("#223344", "темна"), "б": ("#ddeeff", "світла")}, ["а", "б"])
            вих.append(dict(профіль=шлях.stem, джерело=дж, бік=бік, входи=входи,
                            ранг=ранг, пояснення=пояснення,
                            самозвіт=Р.температура_людини(F, {"метал": "золото"}, None)))
    слот = dict(L=[30, 70], C=[20, 40], роль="акцент")
    факт = dict(профілі=вих, вільний=Б.колір_слота(слот),
                заданий=Б.колір_слота(dict(слот, дуга_тону=[100, 120])),
                порожній=dict(ранг=Р.ранг({}, {"а": ("#557755", "а")}, ["а"]),
                              чекліст=С.входи_палітри({})))
    print(json.dumps(факт, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
