"""Перевіряє повний вихід основ для її відповідей за невиміряного портрета."""
import json, pathlib, sys

К = pathlib.Path(__file__).resolve().parents[3]
sys.path.insert(0, str(К / "джерела"))
import міст_вхід as В, міст_основи as О


def main():
    """Не допускає падіння чи точного перепаду при активній осі її відповіді."""
    перевірено = 0
    for шлях in sorted((К / "аудит/проби/жінки").glob("*.json")):
        ж = json.loads(шлях.read_text("utf8"))
        F = В.features(dict(шкіра=ж["skin"], волосся=ж["hair"], очі=ж["eyes"]))[0]
        for барви in ("яскраві", "приглушені"):
            for метал in ("золото", "срібло"):
                вихід = О.основи(F, самозвіт=dict(барви=барви, метал=метал))
                assert all(x["перепад"] is None for x in вихід["рекомендовані"] + вихід["інші"])
                assert вихід["пояснення"]["температура"]["впевненість"] > 0
                перевірено += 1
    print("Самозвіти: перевірено", перевірено, "повних виходів основ без виміряного контрасту.")


if __name__ == "__main__":
    main()
