"""Ціла картка з кадрів стенда: python3 склеїти.py <тека знімків> → n3_kartka_<i>_tsila.png поруч.

Картка на екрані «Образ» живе в області, що гортається сама (`.studio-work`), тож знімок елемента нижче краю області
порожній. Стенд (`рв6_н3.js`, мірило (в)) гортає область і на кожен кадр 390×844 пише межі картки й видимої частини
області (без нерухомої смуги «Напиши…» внизу) у `n3_kartka_<i>_кадри.json`. Тут із кожного кадру береться видима смуга
картки й кладеться на її місце від верху картки.
"""
import json
import sys
from pathlib import Path

from PIL import Image

Т = Path(sys.argv[1])
for опис in sorted(Т.glob('n3_kartka_*_кадри.json')):
    кадри = json.loads(опис.read_text())
    if not кадри:
        continue
    перший = кадри[0]
    ліво, право = round(перший['ліво']), round(перший['право'])
    висота = round(перший['низ'] - перший['верх'])
    ціла = Image.new('RGB', (право - ліво, висота), 'white')
    заповнено = 0
    for к in кадри:
        верх_смуги = max(к['верх'], к['вікно_верх'])
        низ_смуги = min(к['низ'], к['вікно_низ'])
        if низ_смуги <= верх_смуги:
            continue
        з = round(верх_смуги - к['верх'])
        до = round(низ_смуги - к['верх'])
        if до <= заповнено:
            continue
        з = max(з, заповнено)
        смуга = Image.open(Т / к['файл']).crop((ліво, round(к['верх']) + з, право, round(к['верх']) + до))
        ціла.paste(смуга, (0, з))
        заповнено = до
    і = опис.name.split('_')[2]
    ціла.save(Т / f'n3_kartka_{і}_tsila.png')
    print(f'картка {і}: кадрів {len(кадри)}, висота {висота}, складено {заповнено}')
