"""Проба «фішку атласу називає модель, що бачить фото»: аркуші галерей, аркуші атласу й запити оглядачам.

Наряд `Річ-колір-вимір-фішка-з-фото` (18.11). Запис кольору — той самий, що в `аудит/звіти/опис-речі-кодом/`
(`запис.py`, `в2/осі.json`): фішка Манселла, проміжок чи `?`. Речі — 40 `sproba1` (калібрування допуску), 40 `sproba2`
(перевірка) і запасні `sproba2/41`, `sproba2/46` (у переліку втрат зворотного перекладу, свотчів нема). Слова кольору —
записи прогону 1 звіту (`в2/переклад_1.json`, пари `слова`): оглядач бачить фото й свої слова, свотчів, лічби й фішок
перекладу — ні.

Два варіанти, кожен — окремі свіжі оглядачі:
- А — фото й слова; фішку оглядач називає сам;
- Б — фото, слова й аркуш фішок атласу довкола ділянки слів (ділянка — фішка перекладу з допуском слів звіту,
  `допуск.json`, ще крок сітки на кожен бік); оглядач обирає найближчу або називає фішку поза аркушем.

Речі перемішано зерном і названо `р01…`, щоб оглядач не бачив набору й номера; ключ — `ключ.json`.

    python3 -I аудит/проби/річ_колір_фішка_з_фото/запит.py <тека_поза_репозиторієм> [пачок]
        → <тека>/р*_г*.jpg (галерея), <тека>/р*_к*.png (атлас), <тека>/запит_<А|Б>_<n>.md;
          тут — `ключ.json`, `речі.tsv`, `аркуші.tsv` (розмір кожного зображення — для лічби токенів)
"""
