def підставити(запис, фішки):
    """Запис із фішками оглядача на місцях кольорів (порядок `кольори_запису`), частка — з вихідного кольору."""
    черга = list(фішки)

    def нова(старий):
        ф = черга.pop(0).strip()
        return ф + (" " + старий.rsplit(" ", 1)[1] if старий.endswith("%") else "")
    результат = []
    for ч in запис:
        ч = dict(ч)
        if "кольори" in ч:
            ч["кольори"] = [нова(к) for к in ч["кольори"]]
        if "візерунок" in ч:
            ч["візерунок"] = [{**ш, **({"кольори": [нова(к) for к in ш["кольори"]]} if "кольори" in ш else {})}
                              for ш in ч["візерунок"]]
        результат.append(ч)
    if черга:
        raise З.Хиба(f"зайві фішки: {черга}")
    return З.перевірити(результат)


