"""Лічба проби «фішку називає модель, що бачить фото»: кодом, без очей.

Шляхи (той самий запис звіту `аудит/звіти/опис-речі-кодом/`, різниться лише фішка кольору):
- ДО — переклад слів, прогін 1 звіту (`в2/переклад_1.json`), допуск слів звіту (`в2/допуск.json`);
- А — фішку назвав оглядач, що бачив фото й свої слова (`відповіді_А.json`);
- Б — те саме з аркушем атласу довкола ділянки слів (`відповіді_Б.json`);
- правило — переклад слів без фото з правилом «підтон зсуває тон фішки» (`переклад_правило.json`).
У А і Б фішки підставлено в запис прогону 1 на місця його кольорів (частка лишається), решта запису та сама.

Допуск кожного шляху калібровано на `sproba1` (функції звіту, покриття 0.9) — вужчий допуск і є вужча ділянка;
перевірка — на 49 свотчах `sproba2`, яких калібрування не бачило. Свотчі, ознаки, ділянки, ΔE2000 — функції
`лічба.py` і `запис.py` звіту без зміни.

    python3 -I аудит/проби/річ_колір_фішка_з_фото/лічба.py              → підсумок.json, лічба_кольору.tsv, підтон.tsv
    python3 -I аудит/проби/річ_колір_фішка_з_фото/лічба.py зворотний <тека>  → записи_для_зворотного.json (+ ключ у теку)
    python3 -I аудит/проби/річ_колір_фішка_з_фото/лічба.py зворотний_звести → зворотний_підсумок.json
"""
