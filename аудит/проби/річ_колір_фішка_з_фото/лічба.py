# ─── точний код: фішка запису — найближча до свотча фішка атласу чи її сусідка ───
@lru_cache(maxsize=None)
def lab_атласу(H, V, C):
    """Lab фішки атласу (H у кроках 1…100, None — N) або None, коли такої фішки в атласі нема."""
    if H is None:
        return Л.lab_манселла(5.0, V, 1e-6)
    try:
        lab, _ = Л.ПРЯМЕ(H, min(V, 9.99), C)
    except Exception:
        return None
    lab = tuple(map(float, lab))
    return lab


def фішка_свотча(hex_):
    """Найближча до свотча фішка атласу за ΔE2000: (H | None, V, C) серед сусідів округлення його Манселла й N."""
    H, V, C = Л.манселл_свотча(hex_)
    lab = Л.простір.hx(hex_)
    Vs = sorted(З.СВІТЛОТИ, key=lambda x: abs(x - V))[:3]
    Cs = sorted(З.ХРОМИ, key=lambda x: abs(x - C))[:3]
    H0 = round(H / 2.5) * 2.5
    Hs = {((H0 + 2.5 * k - 1) % 100) + 1 for k in range(-2, 3)}
    кандидати = [(None, v, 0.0) for v in Vs] + [(h, v, c) for h in Hs for v in Vs for c in Cs]
    оцінки = [(Л.de2000(л, lab), к) for к in кандидати if (л := lab_атласу(*к)) is not None]
    return min(оцінки)[1]


def фішки_запису(к):
    """Усі фішки атласу, які називає колір запису (проміжок — кожна в ньому); None — колір без коду («?», «різні»)."""
    if к["різні"] or к["V"] is None or к["C"] is None or к["H"] is None:
        return None
    Vs = [v for v in З.СВІТЛОТИ if к["V"][0] - 1e-9 <= v <= к["V"][1] + 1e-9]
    if к["H"] == "N":
        return {(None, v, 0.0) for v in Vs}
    Cs = [c for c in З.ХРОМИ if к["C"][0] - 1e-9 <= c <= к["C"][1] + 1e-9]
    дуга = (к["H"][1] - к["H"][0]) % 100
    Hs = [((к["H"][0] + 2.5 * i - 1) % 100) + 1 for i in range(int(round(дуга / 2.5)) + 1)]
    return {(h, v, c) for h in Hs for v in Vs for c in Cs}


def кроки(а, б):
    """Кроки сітки між двома фішками по осях (тон, світлота, хрома); N — хрома 0, тон будь-який при хромі ≤ 1."""
    (Ha, Va, Ca), (Hb, Vb, Cb) = а, б
    сітка_c = (0.0,) + З.ХРОМИ
    dv = abs(З.СВІТЛОТИ.index(Va) - З.СВІТЛОТИ.index(Vb))
    dc = abs(сітка_c.index(Ca) - сітка_c.index(Cb))
    if Ha is None or Hb is None:
        dh = 0
    else:
        dh = round(abs(тон_різниця(Ha, Hb)) / 2.5)
    return dh, dv, dc


def назва_фішки(ф):
    H, V, C = ф
    v = f"{V:g}"
    if H is None:
        return f"N {v}"
    сектор, n = divmod(H - 1e-9, 10)
    return f"{(n if n > 1e-6 else 10):g}{'R YR Y GY G BG B PB P RP'.split()[int(сектор)]} {v}/{C:g}"


def точність(колір, hex_):
    """(вирок, кроки тон/світлота/хрома до найближчої фішки свотча, ця фішка); вирок: «та сама» — фішка запису й
    найближча до свотча збігаються; «сусідня» — на один крок однієї осі; «ні»; «без коду» (`?`, «різні»)."""
    if not колір:
        return "без коду", "", ""
    колір = колір.rsplit(" ", 1)[0] if колір.endswith("%") else колір
    ціль = фішка_свотча(hex_)
    фішки = фішки_запису(З.розібрати_колір(колір))
    if not фішки:
        return "без коду", "", назва_фішки(ціль)
    к = min((кроки(ф, ціль) for ф in фішки), key=lambda к: (sum(к), max(к)))
    вирок = "та сама" if sum(к) == 0 else "сусідня" if sum(к) == 1 else "ні"
    return вирок, "/".join(map(str, к)), назва_фішки(ціль)


ВИРОКИ = ("та сама", "сусідня", "ні", "без коду")


def чому_ні(рядки):
    """Серед «ні»: скільки промахнулись тоном, світлотою, хромою (крок і більше) і медіана суми кроків."""
    к = [tuple(map(int, р["кроки"].split("/"))) for р in рядки if р["точний"] == "ні"]
    с = sorted(sum(x) for x in к)
    return {"ні": len(к), "тон": sum(x[0] > 0 for x in к), "світлота": sum(x[1] > 0 for x in к),
            "хрома": sum(x[2] > 0 for x in к), "лише_одна_вісь": sum(sum(1 for y in x if y) == 1 for x in к),
            "сума_кроків_медіана": с[len(с) // 2] if с else None}


def тон_різниця(a, b):
    """Знакова різниця тонів b − a по колу, у кроках ASTM (−50…50]."""
    d = (b - a) % 100
    return d - 100 if d > 50 else d


def підтон(прог, допуски):
    """Для речей ВТРАТИ + БЕЖЕВІ: тон фішки кожного шляху проти тону свотча й тону фішки слів (ДО)."""
    рядки = []
    за_шляхом = {ш: {(н_, н, поз): (рядок, к) for н_ in ("sproba1", "sproba2")
                     for н, поз, _, _, _, рядок, к in Л.пари(н_, п)} for ш, п in прог.items()}
    for ключ in БЕЖЕВІ + ВТРАТИ:
        набір, номер = ключ.split("/")
        for н, поз, h, (Hs, Vs, Cs), lab, _, _ in Л.пари(набір, прог["ДО"]):
            if f"{набір}/{н}" != ключ or поз != 1:
                continue
            р = dict(річ=ключ, свотч_HVC=f"{Hs:.1f} {Vs:.2f} {Cs:.2f}")
            до = за_шляхом["ДО"].get((набір, н, поз), (None, None))[1]
            H0 = З.середина(до)[0] if до else None
            for ш in прог:
                рядок, к = за_шляхом[ш].get((набір, н, поз), (None, None))
                р[f"{ш}_фішка"] = рядок or ""
                р[f"{ш}_точний"] = точність(рядок, h)[0]
                if к is None or к["різні"]:
                    continue
                H = З.середина(к)[0]
                т = Л.точка(к)
                if т is not None:
                    р[f"{ш}_ΔE"] = round(Л.de2000(т, lab), 2)
                if Cs <= 0.5 or H is None:
                    continue
                р[f"{ш}_тон_від_свотча"] = round(тон_різниця(Hs, H), 2)
                if ш != "ДО" and H0 is not None:
                    бік_свотча = тон_різниця(H0, Hs)
                    зсув = тон_різниця(H0, H)
                    р[f"{ш}_на_боці_свотча"] = "так" if (abs(бік_свотча) <= 1.25 and abs(зсув) <= 1.25) or \
                        (abs(бік_свотча) > 1.25 and зсув * бік_свотча > 0) else "ні"
            рядки.append(р)
    return рядки


