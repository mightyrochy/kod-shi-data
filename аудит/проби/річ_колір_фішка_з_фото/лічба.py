sys.path.insert(0, str(ЗВІТ))
_опис = importlib.util.spec_from_file_location("лічба_звіту", ЗВІТ / "лічба.py")
Л = importlib.util.module_from_spec(_опис)
_опис.loader.exec_module(Л)
З = Л.З
З.ОСІ = json.loads((ЗВІТ / "в2/осі.json").read_text(encoding="utf-8"))
ЗЕРНО = 20261118
# речі, де зворотний переклад звіту загубив відтінок кольору (16 з 17 втрат; sproba1/10 — ширина смуги, не колір),
# і бежеві № 2, 3, 30, 32, 39 sproba2 з наряду
ВТРАТИ = ["sproba1/9", "sproba1/17", "sproba1/15", "sproba2/27", "sproba1/32", "sproba2/36", "sproba1/38", "sproba1/5",
          "sproba1/6", "sproba2/41", "sproba2/37", "sproba1/30", "sproba2/40", "sproba1/14", "sproba2/46", "sproba1/18"]
БЕЖЕВІ = ["sproba2/2", "sproba2/3", "sproba2/30", "sproba2/32", "sproba2/39"]


def прочитати_tsv(шлях):
    with open(шлях, encoding="utf-8") as ф:
        return list(csv.DictReader(ф, delimiter="\t"))


def прогін_із_файлу(шлях):
    """Як `прочитати_прогін` звіту, але з довільного файлу."""
    сирі = json.loads(шлях.read_text(encoding="utf-8"))
    р = {}
    for ключ, річ in сирі.items():
        try:
            канон, хиба = З.перевірити(річ["запис"]), ""
        except (З.Хиба, KeyError, TypeError, ValueError) as х:
            канон, хиба = None, str(х)
        р[ключ] = dict(запис=канон, хиба=хиба, не_лягло=(річ.get("не_лягло") or "").strip(),
                       слова=[(к, " ".join(с.lower().split())) for к, с in річ.get("слова") or []])
    return р


def підставити(запис, фішки):
    """Запис із фішками оглядача на місцях кольорів (порядок `кольори_запису`), частка — з вихідного кольору."""
    черга = list(фішки)

    def нова(старий):
        ф = черга.pop(0).strip()
        return ф + (" " + старий.rsplit(" ", 1)[1] if старий.endswith("%") else "")
    результат = []
    for ч in запис:
        ч = dict(ч)
        if "кольори" in ч:
            ч["кольори"] = [нова(к) for к in ч["кольори"]]
        if "візерунок" in ч:
            ч["візерунок"] = [{**ш, **({"кольори": [нова(к) for к in ш["кольори"]]} if "кольори" in ш else {})}
                              for ш in ч["візерунок"]]
        результат.append(ч)
    if черга:
        raise З.Хиба(f"зайві фішки: {черга}")
    return З.перевірити(результат)


def прогін_фото(до, варіант):
    ключ = json.loads((ТЕКА / "ключ.json").read_text(encoding="utf-8"))
    відповіді = json.loads((ТЕКА / f"відповіді_{варіант}.json").read_text(encoding="utf-8"))
    р = {}
    for т, к in ключ.items():
        try:
            запис, хиба = підставити(до[к]["запис"], відповіді[т]["кольори"]), ""
        except (З.Хиба, KeyError, TypeError, ValueError, IndexError) as х:
            запис, хиба = None, str(х)
        р[к] = dict(запис=запис, хиба=хиба, не_лягло="", слова=[], примітка=відповіді.get(т, {}).get("примітка", ""))
    return р


def прогони():
    до = Л.прочитати_прогін(ЗВІТ / "в2", 1)
    р = {"ДО": до, "А": прогін_фото(до, "А"), "Б": прогін_фото(до, "Б")}
    if (ТЕКА / "переклад_правило.json").exists():
        р["правило"] = прогін_із_файлу(ТЕКА / "переклад_правило.json")
    return р


def тон_різниця(a, b):
    """Знакова різниця тонів b − a по колу, у кроках ASTM (−50…50]."""
    d = (b - a) % 100
    return d - 100 if d > 50 else d


def підтон(прог, допуски):
    """Для речей ВТРАТИ + БЕЖЕВІ: тон фішки кожного шляху проти тону свотча й тону фішки слів (ДО)."""
    рядки = []
    за_шляхом = {ш: {(н_, н, поз): (рядок, к) for н_ in ("sproba1", "sproba2")
                     for н, поз, _, _, _, рядок, к in Л.пари(н_, п)} for ш, п in прог.items()}
    for ключ in БЕЖЕВІ + ВТРАТИ:
        набір, номер = ключ.split("/")
        for н, поз, h, (Hs, Vs, Cs), lab, _, _ in Л.пари(набір, прог["ДО"]):
            if f"{набір}/{н}" != ключ or поз != 1:
                continue
            р = dict(річ=ключ, свотч_HVC=f"{Hs:.1f} {Vs:.2f} {Cs:.2f}")
            до = за_шляхом["ДО"].get((набір, н, поз), (None, None))[1]
            H0 = З.середина(до)[0] if до else None
            for ш in прог:
                рядок, к = за_шляхом[ш].get((набір, н, поз), (None, None))
                р[f"{ш}_фішка"] = рядок or ""
                if к is None or к["різні"]:
                    continue
                H = З.середина(к)[0]
                т = Л.точка(к)
                if т is not None:
                    р[f"{ш}_ΔE"] = round(Л.de2000(т, lab), 2)
                if Cs <= 0.5 or H is None:
                    continue
                р[f"{ш}_тон_від_свотча"] = round(тон_різниця(Hs, H), 2)
                if ш != "ДО" and H0 is not None:
                    бік_свотча = тон_різниця(H0, Hs)
                    зсув = тон_різниця(H0, H)
                    р[f"{ш}_на_боці_свотча"] = "так" if (abs(бік_свотча) <= 1.25 and abs(зсув) <= 1.25) or \
                        (abs(бік_свотча) > 1.25 and зсув * бік_свотча > 0) else "ні"
            рядки.append(р)
    return рядки


def головне():
    прог = прогони()
    підсумок, усі = {}, []
    допуски = {"ДО": json.loads((ЗВІТ / "в2/допуск.json").read_text(encoding="utf-8"))}
    for ш, п in прог.items():
        хиби = {к: р["хиба"] for к, р in п.items() if р["хиба"] and (к.startswith("sproba"))}
        if ш != "ДО":
            допуски[ш] = Л.калібрувати(Л.пари("sproba1", п), Л.ПОКРИТТЯ)
        д = допуски[ш]
        рядки2 = Л.лічба_кольору("sproba2", п, д)
        підсумок[ш] = {"допуск": д, "хибних_записів": хиби,
                       "sproba2": Л.звести(рядки2),
                       "sproba2_з_допуском_слів": Л.звести(Л.лічба_кольору("sproba2", п, допуски["ДО"])),
                       "sproba1": Л.звести(Л.лічба_кольору("sproba1", п, д))}
        for р in рядки2:
            р["шлях"] = ш
            р["примітка"] = п.get(f"sproba2/{р['номер']}", {}).get("примітка", "")
        усі += рядки2
        з_e = sorted((р for р in рядки2 if "ΔE2000_середини" in р), key=lambda р: -р["ΔE2000_середини"])
        підсумок[ш]["найгірші_5"] = [{к: р.get(к) for к in ("номер", "позиція", "свотч_HVC", "колір",
                                                            "ΔE2000_середини", "примітка")} for р in з_e[:5]]
    поля = ["шлях", "набір", "номер", "позиція", "свотч", "свотч_HVC", "колір", "у_клітинці", "у_ділянці", "ширина_H",
            "ширина_V", "ширина_C", "ΔE2000_середини"] + [f"{д}_{о}" for д in ("середина", "ділянка")
                                                           for о in ("родина", "підтон", "світлота", "хрома")] + ["примітка"]
    with open(ТЕКА / "лічба_кольору.tsv", "w", encoding="utf-8", newline="") as ф:
        п = csv.DictWriter(ф, поля, delimiter="\t", lineterminator="\n", restval="")
        п.writeheader()
        п.writerows(усі)
    рядки = підтон(прог, допуски)
    поля = ["річ", "свотч_HVC"] + [f"{ш}_{x}" for ш in прог for x in ("фішка", "ΔE", "тон_від_свотча", "на_боці_свотча")
                                   if not (ш == "ДО" and x == "на_боці_свотча")]
    with open(ТЕКА / "підтон.tsv", "w", encoding="utf-8", newline="") as ф:
        п = csv.DictWriter(ф, поля, delimiter="\t", lineterminator="\n", restval="")
        п.writeheader()
        п.writerows(рядки)
    for ш in прог:
        з_тоном = [р for р in рядки if f"{ш}_тон_від_свотча" in р]
        підсумок[ш]["підтон"] = {
            "речей_з_тоном_свотча": len(з_тоном),
            "тон_у_межах_кроку_від_свотча": sum(abs(р[f"{ш}_тон_від_свотча"]) <= 2.5 for р in з_тоном),
            "тон_від_свотча_медіана": statistics.median(abs(р[f"{ш}_тон_від_свотча"]) for р in з_тоном) if з_тоном else None,
            **({"на_боці_свотча": sum(р.get(f"{ш}_на_боці_свотча") == "так" for р in з_тоном)} if ш != "ДО" else {}),
            "бежеві_на_боці_свотча": sum(р.get(f"{ш}_на_боці_свотча") == "так" for р in з_тоном if р["річ"] in БЕЖЕВІ)
            if ш != "ДО" else None,
        }
    # токени: розмір контексту субагента на річ; зображення — оцінка w·h/750 після вписування в 1568 px
    т = прочитати_tsv(ТЕКА / "токени.tsv")
    аркуші = прочитати_tsv(ТЕКА / "аркуші.tsv")

    def токени_зображення(w, h):
        k = min(1.0, 1568 / max(w, h), math.sqrt(1_150_000 / (w * h)))
        return round(w * k * h * k / 750)
    за_видом = {"г": 0, "к": 0}
    for а in аркуші:
        за_видом["к" if "_к" in а["файл"] else "г"] += токени_зображення(int(а["ширина"]), int(а["висота"]))
    речей = len({а["річ"] for а in аркуші})
    for в in ("А", "Б"):
        на_річ = [int(р["токенів_субагента"]) / int(р["речей"]) for р in т if р["варіант"] == в]
        підсумок[в]["токени"] = {"субагент_на_річ_медіана_пачок": round(statistics.median(на_річ)),
                                 "субагент_усього": sum(int(р["токенів_субагента"]) for р in т if р["варіант"] == в)}
    підсумок["Б"]["токени"]["Б_мінус_А_на_річ"] = round(
        (підсумок["Б"]["токени"]["субагент_усього"] - підсумок["А"]["токени"]["субагент_усього"]) / речей)
    підсумок["зображення_оцінка_на_річ"] = {"галерея": round(за_видом["г"] / речей), "атлас": round(за_видом["к"] / речей)}
    (ТЕКА / "підсумок.json").write_text(json.dumps(підсумок, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    for ш in прог:
        с = підсумок[ш]["sproba2"]
        сл = підсумок[ш]["sproba2_з_допуском_слів"]
        print(ш, "хиб", len(підсумок[ш]["хибних_записів"]), "| ΔE", с["ΔE2000_середини_медіана"], "| у ділянці",
              с["у_ділянці"], "з", с["свотчів"], "ширина", с["ширина_медіана"], "| з допуском слів", сл["у_ділянці"],
              "| середина", с["середина"], "| ділянка певно", {о: v["певно"] for о, v in с["ділянка"].items()},
              "| підтон", підсумок[ш]["підтон"])


# ─── зворотний переклад ───
def зворотний(куди):
    прог = прогони()
    рядки = [(ш, к) for ш in прог for к in ВТРАТИ + ["sproba1/10"] if прог[ш].get(к, {}).get("запис")]
    random.Random(ЗЕРНО).shuffle(рядки)
    таємні = {f"з{i + 1:03d}": [ш, к] for i, (ш, к) in enumerate(рядки)}
    (ТЕКА / "записи_для_зворотного.json").write_text(json.dumps(
        {т: З.рядком(прог[ш][к]["запис"]) for т, (ш, к) in таємні.items()}, ensure_ascii=False, indent=0) + "\n",
        encoding="utf-8")
    (куди / "ключ_зворотного.json").write_text(json.dumps(таємні, ensure_ascii=False), encoding="utf-8")
    print(len(таємні), "записів")


def зворотний_звести():
    слова = {р["річ"]: р["корені"].split() for р in прочитати_tsv(ТЕКА / "слова_підтону.tsv")}
    таємні = json.loads((ТЕКА / "ключ_зворотного.json").read_text(encoding="utf-8"))
    нові = json.loads((ТЕКА / "зворотний_переклад.json").read_text(encoding="utf-8"))
    # ДО звіту: його власний зворотний переклад (інший відновлювач, той самий запис прогону 1)
    ключ_звіту = json.loads((ЗВІТ / "в2/ключ_записів.json").read_text(encoding="utf-8"))
    старі = json.loads((ЗВІТ / "в2/зворотний_переклад.json").read_text(encoding="utf-8"))
    є = lambda текст, к: any(с in текст.lower() for с in слова[к])
    рядки, підсумок = [], {}
    for т, к in ключ_звіту.items():
        if к in слова:
            рядки.append(dict(шлях="ДО_звіту", річ=к, повернуто="так" if є(старі[т], к) else "ні", опис=старі[т]))
    for т, (ш, к) in таємні.items():
        if к in слова:
            рядки.append(dict(шлях=ш, річ=к, повернуто="так" if є(нові[т], к) else "ні", опис=нові[т]))
    for р in рядки:
        г = підсумок.setdefault(р["шлях"], {"речей": 0, "повернуто": 0, "речі": []})
        г["речей"] += 1
        if р["повернуто"] == "так":
            г["повернуто"] += 1
            г["речі"].append(р["річ"])
    with open(ТЕКА / "зворотний_лічба.tsv", "w", encoding="utf-8", newline="") as ф:
        п = csv.DictWriter(ф, ["шлях", "річ", "повернуто", "опис"], delimiter="\t", lineterminator="\n")
        п.writeheader()
        п.writerows(sorted(рядки, key=lambda р: (р["шлях"], р["річ"])))
    (ТЕКА / "зворотний_підсумок.json").write_text(json.dumps(підсумок, ensure_ascii=False, indent=1) + "\n",
                                                   encoding="utf-8")
    print(json.dumps({ш: {к: v for к, v in г.items() if к != "речі"} for ш, г in підсумок.items()}, ensure_ascii=False))


if __name__ == "__main__":
    if sys.argv[1:2] == ["зворотний"]:
        зворотний(Path(sys.argv[2]))
    elif sys.argv[1:2] == ["зворотний_звести"]:
        зворотний_звести()
    else:
        головне()
