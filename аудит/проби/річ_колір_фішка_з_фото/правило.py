"""Дешевший шлях без фото: переклад слів у запис із правилом «підтон зсуває тон фішки» (звіт, розділ 8, п.2).

Запит — той самий `аудит/звіти/опис-речі-кодом/в2/запит_перекладу.md`, у якому рядок про підтон замінено правилом
нижче; описи — 90 коротких назв `sproba1`, `sproba2` з `описи.tsv` звіту. Перекладач — свіжий субагент, що бачить лише
запит і описи; відповідь — `переклад_правило.json` тут (формат звіту: запис, слова, не_лягло).

    python3 -I аудит/проби/річ_колір_фішка_з_фото/правило.py <тека_поза_репозиторієм>
        → запит_правило.md тут, <тека>/описи_90.tsv
"""
import sys
from pathlib import Path

ТЕКА = Path(__file__).resolve().parent
ЗВІТ = ТЕКА.parents[1] / "звіти/опис-речі-кодом"
БУЛО = "«з …им підтоном, відливом» — на крок до названого тону."
СТАЛО = ("«з …им підтоном, відливом» — на крок до названого тону. У майже-нейтральному кольорі (хрома 1–4: беж,\n"
         "  тауп, сіро-коричневий, пудра, айворі, приглушений бордо, сіро-блакитний) слово підтону — «рожевуватий»,\n"
         "  «бузковий», «сливовий», «винний», «лососевий», «оливковий», «зеленкуватий», «аквамариновий», «жовтуватий»\n"
         "  тощо, і в складеній назві («рожевувато-бежевий», «сливово-шоколадний») — зсуває тон фішки на два кроки\n"
         "  (5 одиниць) до тону підтону, а не на один: «рожевуватий тауп» — `10R 5/2`, а не `5YR 5/2`; «бузковий беж» —\n"
         "  `2.5YR 7/2`, а не `10YR 7/2`. Основна назва дає світлоту й хрому, підтон — тон.")


def головне(куди):
    запит = (ЗВІТ / "в2/запит_перекладу.md").read_text(encoding="utf-8")
    assert БУЛО in запит
    (ТЕКА / "запит_правило.md").write_text(запит.replace(БУЛО, СТАЛО), encoding="utf-8")
    куди.mkdir(parents=True, exist_ok=True)
    рядки = (ЗВІТ / "описи.tsv").read_text(encoding="utf-8").splitlines()
    (куди / "описи_90.tsv").write_text("\n".join([рядки[0]] + [р for р in рядки[1:] if р.startswith("sproba")]) + "\n",
                                       encoding="utf-8")
    print("запит_правило.md;", sum(р.startswith("sproba") for р in рядки), "описів →", куди / "описи_90.tsv")


if __name__ == "__main__":
    головне(Path(sys.argv[1]))
