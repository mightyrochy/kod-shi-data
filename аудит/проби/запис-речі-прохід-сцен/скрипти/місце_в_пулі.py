"""Зіставляє місце 3004 записаних речей с1–с8 з рішенням паспорта. Запуск із кореня репозиторію."""
import argparse
from collections import Counter
import csv
import gzip
import hashlib
import json
from pathlib import Path
import random
import sys

sys.path.insert(0, str(Path.cwd() / "джерела"))
from ядро import пул, річ, записи_речей
from ядро.поняття import НЕВІДОМО, Ситуація

ЗВІРКА = Path("аудит/звіти/стилістка-вибір-з-пулу/рядки.csv.gz")
АРХІВ = Path(__file__).resolve().parents[1] / "дані" / "записи_речі.json.gz"
БЕЗ_МІСЦЯ = {"ж-11077@skripka.com.ua", "ж53-8e49ecc98538146b057a@theoriginals.com.ua"}


def мірило(ід, каталог, мітки):
    """Очікуване місце за рішенням паспорта на кодах записаного проходу."""
    слот = мітки.get("слот", {}).get("значення")
    тип = мітки.get("тип", {}).get("значення")
    if ід in БЕЗ_МІСЦЯ or слот is None:
        return НЕВІДОМО
    if (каталог, слот) == ("верхній_шар", "верх") or тип in ("jacket", "blazer", "cardigan", "vest"):
        return "верхній_шар"
    if тип in ("headband", "bow", "hair_clip", "hair_tie"):
        return "волосся"
    if тип == "jumpsuit":
        return "сукня"
    if слот in ("намисто", "кольє") or тип in ("necklace", "collar_necklace"):
        return "кольє"
    return слот


def каталог_пулів(записи):
    """Збирає унікальні ідентифікатори та записані місця кандидатів с1–с8."""
    каталог = {}
    with gzip.open(ЗВІРКА, "rt", encoding="utf-8") as файл:
        for рядок in csv.DictReader(файл):
            ід = рядок["ід"]
            if ід not in записи:
                continue
            слот = рядок["слот"]
            assert слот == каталог.setdefault(ід, {"id": ід, "слот": слот})["слот"], ід
    assert len(каталог) == 3004
    return каталог


def записати_вибірку(шлях, вибірка, місця):
    """Зберігає 60 назв і галерей із запропонованим місцем без відомостей про джерело."""
    основа = {ід.split("@")[0]: ід for ід in вибірка}
    фото = {}
    with gzip.open("каталог_записи_v1.jsonl.gz", "rt", encoding="utf-8") as файл:
        for запис in map(json.loads, файл):
            if запис.get("ід") in основа:
                фото[основа[запис["ід"]]] = запис
    assert set(фото) == set(вибірка)
    with шлях.open("w", encoding="utf-8") as файл:
        for номер, ід in enumerate(вибірка, 1):
            запис = фото[ід]
            рядок = {"ряд": номер, "назва": запис["назва"], "кадри": [к for к in запис["кадри"] if к.startswith("http")],
                     "місце": місця[ід]}
            print(json.dumps(рядок, ensure_ascii=False), file=файл)


def замір(каталог, записи, увімкнено):
    """Вимірює байти пулу та звіряє місце перед відсівом і в кожному рядку пулу."""
    рядки = list(каталог.values())
    if увімкнено:
        рядки = записи_речей.вкласти(рядки, записи)
    місця = {рядок["id"]: річ.читати(рядок).слот for рядок in рядки}
    результат = пул.зібрати(Ситуація(1), 1, 178637, рядки)
    кандидати = {р.ід: р.слот for р in результат.записи.values()}
    assert len(кандидати) + len(результат.відкинуто) == len(рядки)
    assert all(місця[ід] == слот for ід, слот in кандидати.items())
    байти = json.dumps(результат.в_json(), ensure_ascii=False, separators=(",", ":")).encode()
    print("нові" if увімкнено else "без", len(байти), hashlib.sha256(байти).hexdigest(), "рядків", len(кандидати))
    return місця, кандидати


def головна():
    """Друкує відхилення від паспорта та за потреби готує вибірку для іншого оглядача."""
    аргументи = argparse.ArgumentParser(description=__doc__)
    аргументи.add_argument("--вибірка", type=Path)
    шлях = аргументи.parse_args().вибірка
    with gzip.open(АРХІВ, "rt", encoding="utf-8") as файл:
        записи = json.load(файл)
    каталог = каталог_пулів(записи)
    записи = {ід: записи[ід] for ід in каталог}
    очікувані = {ід: мірило(ід, р["слот"], записи[ід]["мітки"]) for ід, р in каталог.items()}
    без_місця = [ід for ід, слот in очікувані.items() if слот == НЕВІДОМО]
    замір(каталог, записи, увімкнено=False)
    місця, кандидати = замір(каталог, записи, увімкнено=True)
    старі = {ід: р["слот"] for ід, р in каталог.items()}
    історичні = {ід: р["мітки"].get("слот", {}).get("значення") for ід, р in записи.items()}
    print("розходжень каталогу із сирими мітками", sum(слот is not None and слот != старі[ід]
                                                      for ід, слот in історичні.items()))
    зміни = sorted(ід for ід, слот in очікувані.items() if слот != НЕВІДОМО and слот != старі[ід])
    розходження = [ід for ід, слот in очікувані.items() if слот != НЕВІДОМО and слот != місця[ід]]
    print("розходжень із рішенням паспорта", len(зміни), "→", len(розходження))
    print("перенесення за рішенням", dict(Counter((старі[ід], очікувані[ід]) for ід in зміни)))
    print("без місця", ", ".join(sorted(без_місця)))
    if шлях:
        вибірка = random.Random(4938).sample(зміни, 60)
        записати_вибірку(шлях, вибірка, очікувані)
    зайві_в_пулі = set(без_місця).intersection(кандидати)
    assert not розходження and not зайві_в_пулі, (розходження[:5], sorted(зайві_в_пулі))


if __name__ == "__main__":
    головна()
