#!/usr/bin/env python3
"""Зведення проходу (наряд `Запис-речі-прохід-сцен`): журнал проходу → читач (`запис_речі.розібрати`) → записи речей
(`дані/записи_речі.json.gz`: повний ід з крамницею → {опис, мітки, модель, зусилля, дата, версія_міток}), лічба відкинутих
відповідей з причинами, частка невідомого кольору, ціна (г). Запуск з кореня: python3 -I <цей файл> <журнал.jsonl[.gz]>… (перший — основний прохід, далі — продовження)"""
import collections, csv, gzip, json, statistics, sys
from pathlib import Path
К = Path(__file__).resolve().parents[4]; sys.path.insert(0, str(К / "джерела"))
import запис_речі
Д = К / "аудит/проби/запис-речі-прохід-сцен/дані"
усі_виклики = [json.loads(л) for шлях in sys.argv[1:] for л in (gzip.open(шлях, "rt", encoding="utf-8") if шлях.endswith(".gz") else open(шлях, encoding="utf-8"))]  # кілька журналів проходів: перший ok речі переважає
журнал, бачені = [], set()  # повтор речі (два одночасних запуски) — лише перша відповідь ok; решта лічиться окремо
for з in усі_виклики:
    if з["ід"] in бачені and з["статус"] == "ok": continue
    if з["статус"] == "ok": бачені.add(з["ід"])
    журнал.append(з)
повторних = sum(1 for з in усі_виклики if з["статус"] == "ok") - sum(1 for з in журнал if з["статус"] == "ok")
повні = {}
for р in csv.DictReader(gzip.open(К / "аудит/звіти/стилістка-вибір-з-пулу/рядки.csv.gz", "rt", encoding="utf-8")):
    if р["ід"]: повні[р["ід"].split("@")[0]] = р["ід"]
перелік = {р["ід"]: р for ф in ("перелік.json", "перелік_нові.json") if (Д / ф).exists() for р in json.load(open(Д / ф, encoding="utf-8"))["речі"]}
for р in перелік.values():
    if р.get("повний"): повні[р["ід"]] = р["повний"]
ок = [з for з in журнал if з["статус"] == "ok"]
записи, відкинуто, причини, без_кадрів, колір = {}, [], collections.Counter(), 0, collections.Counter()
for з in ок:
    р = запис_речі.розібрати(з["текст"])
    if з.get("фото") == 0: без_кадрів += 1
    # відкинуто: відповідь не розібрано взагалі, чи колір відкинуто читачем (мітка «колір» у збоях)
    не_розібрано = not р["мітки"] and not р["опис"] != "невідомо" and any(x["поле"] == "*" for x in р["збої"])
    if не_розібрано:
        відкинуто.append(з["ід"]); причини["не JSON чи не об'єкт"] += 1; continue
    for x in р["збої"]: причини[f'{x["поле"]}: {x["що"]}'[:90]] += 1
    к = р["мітки"].get("колір")
    колір["відомий" if к and к.get("значення") != "невідомо" and к.get("значення") != "не_певний" else
          ("не_певний" if к and к.get("значення") == "не_певний" else
           ("нема кадрів" if з.get("фото") == 0 else "невідомо/нема мітки"))] += 1
    записи[повні.get(з["ід"], з["ід"])] = {"опис": р["опис"], "мітки": р["мітки"], "модель": з["модель"], "зусилля": з["зусилля"],
                                          "дата": з["дата"], "версія_міток": з["версія_міток"]}
json.dump(записи, gzip.open(Д / "записи_речі.json.gz", "wt", encoding="utf-8", compresslevel=9), ensure_ascii=False, separators=(",", ":"))
токени_в = sum(з["вхід_нових"] + з["вхід_кеш_запис"] + з["вхід_кеш_читання"] for з in ок); токени_вих = sum(з["вихід"] for з in ок)
н = len(ок); сек = [з["с"] for з in ок]
підсумок = {"в_переліку": len(перелік), "повторних_викликів_відкинуто": повторних, "у_журналі": len(журнал), "ok": н, "нема_в_каталозі": sum(з["статус"] == "нема" for з in журнал),
            "збоїв_запуску": sum(з["статус"] == "збій" for з in журнал), "записів": len(записи), "відкинуто_читачем": len(відкинуто),
            "причини": причини.most_common(12), "колір": dict(колір), "без_кадрів": без_кадрів,
            "ціна": {"токенів_входу": токени_в, "токенів_виходу": токени_вих, "вхід_нових": sum(з["вхід_нових"] for з in ок),
                     "кеш_запис": sum(з["вхід_кеш_запис"] for з in ок), "кеш_читання": sum(з["вхід_кеш_читання"] for з in ок),
                     "секунд_усього": round(sum(сек)), "с_на_річ_середнє": round(statistics.mean(сек), 2), "с_медіана": statistics.median(сек),
                     "вхід_на_річ": round(токени_в / н), "вихід_на_річ": round(токени_вих / н),
                     "оцінка_30281": {"токенів_входу": round(токени_в / н * 30281), "токенів_виходу": round(токени_вих / н * 30281),
                                      "годин_моделі": round(statistics.mean(сек) * 30281 / 3600, 1)}},
            "моделі": dict(collections.Counter(m for з in ок for m in з.get("моделі", [])))}
(Д / "підсумок.json").write_text(json.dumps(підсумок, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
print(json.dumps(підсумок, ensure_ascii=False, indent=1))
