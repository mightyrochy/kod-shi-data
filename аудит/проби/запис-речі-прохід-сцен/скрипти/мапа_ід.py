#!/usr/bin/env python3
"""Мапа ід (наряд «Запис-речі-прохід-сцен», продовження, п.1): кожен рядок пулу кожного запиту складання → ід каталогу,
без моделі. Рядок пулу не несе ні ід, ні крамниці, ні назви, ні кадру: лише номер `#N·КК` (КК — код крамниці в межах
запиту) і ознаки (ціна, тип, слово кольору, hex, L, родина тону, тканина, крій). Каталог (закріплений коміт виміру
`крамниці-рівна-черга`) проєктується тим самим кодом, що будує рядок пулу (`пакет_моделі.рядки_кандидатів` →
`дріт_моделі.річ(пул=True)`), і ознаки рядка шукають у проєкції.
Щаблі: 1 — повний ключ (ціна, колір, тип, L, L_from, hex, родина, тканина, крій); 2 — послаблений (ціна, тип, колір, L, hex),
лише коли повний нічого не дав; далі — код крамниці запиту: голоси однозначних рядків, один код = одна крамниця.
Статуси: «однозначно» (один кандидат), «за_крамницею» (кілька кандидатів, а код крамниці лишає одного),
«послаблений» (щабель 2, один кандидат), «неоднозначно» (кілька кандидатів лишилось: однакові ознаки в одній крамниці),
«нема» (жодного). Кандидатів за «неоднозначно» не вгадують, а лічать окремо.
Перевірка точності — на рядках, чий ід уже знав звіт `стилістка-вибір-з-пулу` (зіставлення за відбитком записаних обмінів):
розбіжність ід = хибне.
Запуск з кореня: python3 -I <цей файл> --пули <обміни.jsonl стенда> <сцена> — зберегти пули нової сцени;
python3 -I <цей файл> — читає `дані/пули/*.jsonl.gz` і службові обміни моста, пише `дані/мапа_ід.json.gz`,
`дані/мапа_ід_підсумок.json`."""
import collections, csv, gzip, importlib.util, json, pickle, sys
from pathlib import Path
К = Path(__file__).resolve().parents[4]
ПРОБА = К / "аудит/проби/запис-речі-прохід-сцен"
Д = ПРОБА / "дані"
КЕШ = Path("/tmp/мапа_ід_кеш"); КЕШ.mkdir(exist_ok=True)
сп = importlib.util.spec_from_file_location("попередній", К / "аудит/звіти/крамниці-рівна-черга/вимір.py")
П = importlib.util.module_from_spec(сп); sys.modules["попередній"] = П; сп.loader.exec_module(П)
МІСТ = К / "аудит/проби/Живий-через-міст/стенд/службове"
ПОЛЯ1 = ("price", "color", "type", "L", "L_from", "hex", "family", "fabric", "cut")
ПОЛЯ2 = ("price", "type", "color", "L", "hex")


def канон(v):
    if isinstance(v, (list, tuple)):
        v = [канон(x) for x in v]
        if len(v) == 1: return v[0]
        if len(v) == 2 and v[0] == v[1] and not isinstance(v[0], list): return v[0]
        return v
    if isinstance(v, float) and v == int(v): return int(v)
    return None if v == "unknown" else v


def ключ(о, поля): return json.dumps([канон(о.get(к)) for к in поля], ensure_ascii=False, separators=(",", ":"))
def крамниця(ід): return ід.rsplit("@", 1)[-1]


def проєкція():
    """ід → рядок пулу каталогу (кеш у /tmp: збирання коду з коміту ≈ 15 с, проєкція ≈ 20 с)."""
    файл = КЕШ / "проєкція.pkl"
    if файл.exists(): return pickle.load(файл.open("rb"))
    копія = КЕШ / "код"; копія.mkdir(exist_ok=True)
    П.код_з_коміту(копія); sys.path.insert(0, str(копія / "джерела"))
    каталог, _, _ = П.знімок(копія)
    import семплер, дріт_моделі
    from пакет_моделі import рядки_кандидатів
    за_слотом = collections.defaultdict(list)
    for r in каталог: за_слотом[r.get("слот")].append(dict(r, _гілка=семплер.ГІЛКА_ЯДРО, _ранг_пізній=0))
    вих = {}
    for с, rs in за_слотом.items():
        for i in range(0, len(rs), 500):
            for r in рядки_кандидатів(None, None, None, {"_кандидати": {с: rs[i:i + 500]}})[с]:
                о = дріт_моделі.річ(r, пул=True, слот=с); о.pop("knowledge", None); вих[r["id"]] = о
    pickle.dump(вих, файл.open("wb"))
    pickle.dump({r["id"]: {к: r.get(к) for к in ("назва", "ціна", "фото", "group_id", "магазин")} for r in каталог}, (КЕШ / "каталог.pkl").open("wb"))
    return вих


def пули_мосту(сцена, файл):
    """Запити з пулом у службовому обміні моста (як у `стилістка-вибір-з-пулу/дані.py`): ((прохід, рядок), рядки пулу, взяті номери)."""
    for лінія, рядок in enumerate(open(файл, encoding="utf-8"), 1):
        if not рядок.strip(): continue
        о = json.loads(рядок)
        if not о.get("відповідь") or о.get("статус") != 200: continue
        з = о["запит"]; тіло = json.loads(з) if isinstance(з, str) else з
        try: пакет = П.розібрати_json(П.текст_запиту(тіло))
        except (ValueError, IndexError): continue
        if not (isinstance(пакет.get("pool"), dict) and "rows" in пакет["pool"]): continue
        try:
            відповідь = П.розібрати_json("".join(б["text"] for б in json.loads(о["відповідь"]).get("content", []) if б.get("type") == "text"))
        except (ValueError, IndexError): continue
        if not isinstance(відповідь.get("outfits"), list): continue
        рс = П.записи_таблиці(пакет)
        if рс: yield (str(о.get("прохід", 1)), лінія), рс


def зіставити(рядки, інд1, інд2, ід_за_ключем1, ід_за_ключем2):
    """Рядки одного запиту → {n: (ід|None, статус, кандидатів)}."""
    кан = {}
    for р in рядки:
        k1 = ід_за_ключем1.get(ключ(р, ПОЛЯ1), set()); щабель = 1
        if not k1: k1 = ід_за_ключем2.get(ключ(р, ПОЛЯ2), set()); щабель = 2
        кан[р["n"]] = (k1, щабель)
    голоси = collections.defaultdict(collections.Counter)
    for n, (к, щ) in кан.items():
        if len(к) == 1: голоси[n.split("·")[1]][крамниця(next(iter(к)))] += 1
    код_крамниця = {код: next(iter(c)) for код, c in голоси.items() if len(c) == 1}
    # кандидати рядка, звужені крамницею з коду (де код відомий); решта — як є
    звужені = {}
    for n, (к, щ) in кан.items():
        м = код_крамниця.get(n.split("·")[1])
        ф = {i for i in к if крамниця(i) == м} if м and len(к) > 1 else set(к)
        звужені[n] = ф if ф or len(к) <= 1 else set(к)
    # порядок у крамниці: номер N у межах одного коду зростає разом з ід (роздача `номери_речей` іде за `порядок` —
    # за ід; 12574 сусідніх пар звіту: 19 порушень, усі — хибні ід самого звіту), тож річ між двома однозначними
    # сусідами мусить лежати між їхніми ід; річ запиту не стоїть у пулі двічі
    за_кодом = collections.defaultdict(list)
    for n in кан: за_кодом[n.split("·")[1]].append((int(n.split("·")[0][1:]), n))
    ід_рядка = {n: next(iter(ф)) for n, ф in звужені.items() if len(ф) == 1}
    за_порядком = set()
    змінено = True
    while змінено:
        змінено = False
        використані = set(ід_рядка.values())
        for код, список in за_кодом.items():
            список.sort()
            for позиція, (N, n) in enumerate(список):
                if n in ід_рядка or len(звужені[n]) <= 1: continue
                низ = next((ід_рядка[m] for _, m in reversed(список[:позиція]) if m in ід_рядка), None)
                верх = next((ід_рядка[m] for _, m in список[позиція + 1:] if m in ід_рядка), None)
                дозв = {i for i in звужені[n] if (низ is None or i > низ) and (верх is None or i < верх) and i not in використані}
                if len(дозв) < len(звужені[n]): звужені[n] = дозв or звужені[n]
                if len(звужені[n]) == 1:
                    ід_рядка[n] = next(iter(звужені[n])); за_порядком.add(n); використані.add(ід_рядка[n]); змінено = True
        # k нерозв'язаних рядків одного коду з однаковим набором із k кандидатів: іменуємо за порядком
        for код, список in за_кодом.items():
            групи = collections.defaultdict(list)
            for N, n in sorted(список):
                if n not in ід_рядка and len(звужені[n]) > 1: групи[frozenset(звужені[n])].append(n)
            for набір, рядки_ in групи.items():
                if len(набір) == len(рядки_):
                    for n, i in zip(рядки_, sorted(набір)):
                        ід_рядка[n] = i; звужені[n] = {i}; за_порядком.add(n); змінено = True
    вих = {}
    for n, (к, щ) in кан.items():
        if not к: вих[n] = (None, "нема", 0)
        elif n in ід_рядка:
            і = ід_рядка[n]
            вих[n] = (і, "за_порядком" if n in за_порядком else ("за_крамницею" if len(к) > 1 else ("послаблений" if щ == 2 else "однозначно")), len(к))
        else: вих[n] = (None, "неоднозначно", len(звужені[n]))
    return вих


def джерела():
    """(сцена, ((прохід, рядок), рядки пулу))* зі службових обмінів моста й записаних пулів нових сцен."""
    for тека in sorted(МІСТ.iterdir()):
        for ключ_, рс in пули_мосту(тека.name, тека / "обміни.jsonl"): yield тека.name, ключ_, рс
    for файл in sorted((Д / "пули").glob("*.jsonl.gz")):
        for л in gzip.open(файл, "rt", encoding="utf-8"):
            з = json.loads(л); yield з["сцена"], (з["прохід"], з["рядок"]), з["рядки"]


def головна():
    інд = проєкція()
    за1, за2 = collections.defaultdict(set), collections.defaultdict(set)
    for i, о in інд.items(): за1[ключ(о, ПОЛЯ1)].add(i); за2[ключ(о, ПОЛЯ2)].add(i)
    відомі = {}
    for р in csv.DictReader(gzip.open(К / "аудит/звіти/стилістка-вибір-з-пулу/рядки.csv.gz", "rt", encoding="utf-8")):
        відомі[р["запит"], р["n"]] = р["ід"]
    мапа, лічба, точність = {}, collections.defaultdict(collections.Counter), collections.Counter()
    for сцена, (прохід, рядок), рс in джерела():
        з = зіставити(рс, інд, інд, за1, за2)
        ід_запиту = f"{сцена}/{прохід}/{рядок}"
        мапа[ід_запиту] = {n: list(v) for n, v in з.items()}
        сц = сцена.split("_")[0]
        for р in рс:
            ід, ст, k = з[р["n"]]
            лічба[сц]["рядків"] += 1; лічба[сц][ст] += 1
            if ід: лічба[сц]["з_ід"] += 1
            до = відомі.get((ід_запиту, р["n"]))
            if до is not None: лічба[сц]["рядків_з_ід_до"] += 1 if до else 0
            if до:
                точність["звірено"] += 1
                if ід: точність["вірно" if ід == до else "хибно"] += 1; точність[f"вірно_{ст}" if ід == до else f"хибно_{ст}"] += 1
                else: точність["без_ід_після_але_відомий_до"] += 1
    з_ід = {k: v["з_ід"] for k, v in лічба.items()}
    підсумок = {"точність_на_відомих": dict(точність),
                "сцени": {к: {**dict(v), "частка_ід_до_%": round(100 * v["рядків_з_ід_до"] / v["рядків"], 1),
                              "частка_ід_після_%": round(100 * v["з_ід"] / v["рядків"], 1)} for к, v in sorted(лічба.items())}}
    with gzip.open(Д / "мапа_ід.json.gz", "wt", encoding="utf-8", compresslevel=9) as ф: json.dump(мапа, ф, ensure_ascii=False, separators=(",", ":"))
    (Д / "мапа_ід_підсумок.json").write_text(json.dumps(підсумок, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(json.dumps(підсумок, ensure_ascii=False, indent=1))


def записати_пули(файл_обмінів, сцена):
    """Пули запитів складання нового запису стенда (`пройти.py`) → `дані/пули/<сцена>.jsonl.gz` (лише рядки пулу: обміни важать мегабайти)."""
    (Д / "пули").mkdir(exist_ok=True)
    with gzip.open(Д / "пули" / f"{сцена}.jsonl.gz", "wt", encoding="utf-8", compresslevel=9) as ф:
        for (прохід, рядок), рс in пули_мосту(сцена, файл_обмінів):
            ф.write(json.dumps({"сцена": сцена, "прохід": прохід, "рядок": рядок, "рядки": рс}, ensure_ascii=False, separators=(",", ":")) + "\n")


if __name__ == "__main__":
    if len(sys.argv) == 4 and sys.argv[1] == "--пули": записати_пули(sys.argv[2], sys.argv[3])
    else: головна()
