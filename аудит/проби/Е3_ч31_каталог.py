print("\n── рука 2, K-FIT-03 «суд» (`поломки._краї_навпаки`): (тіло, місце, відповідь краю) → хибна порада так/ні: у потоці `краї(суд=True)` і з голої відповіді краю (`_краї_навпаки` без справних знахідок) ──")
for (т, м, в, х, пр), n in sorted(рука2.items()): print(f"   {т:10s} {м:22s} {в:10s} хибна порада в потоці: {'ТАК' if х else 'ні':4s} з голої відповіді краю: {пр:8s} {n}")
