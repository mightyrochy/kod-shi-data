"""Відтворює межі нового правила опор на призначеній голові PR #4042; аргумент — тека її дерева."""
import importlib.util
import pathlib
import sys

def main():
    """Друкує факти незалежної перевірки на переданому дереві голови."""
    шлях = pathlib.Path(sys.argv[1]).resolve() / 'джерела' / 'прилади'
    sys.path.insert(0, str(шлях))
    опис = importlib.util.spec_from_file_location('прилад_4042', шлях / 'корінь_е2_смуга_погоди.py')
    прилад = importlib.util.module_from_spec(опис)
    опис.loader.exec_module(прилад)
    писач = прилад._ПИСАЧ_ОПОР % '("бажання", "вето")'
    випадки = {
        'контроль-без-погоди': (писач, set()),
        'контроль-погода-літералом': (писач.replace('паспорт, поле, внутрішня[поле]',
                                                   'паспорт, "смуга_погоди", внутрішня[поле]'), {2}),
        '16067-розпакування-аргументів': (
            писач.replace('паспорт, поле, внутрішня[поле]', 'паспорт, "смуга_погоди", внутрішня[поле]')
            .replace('"х", опори=[{"уривок": "х"}])', '"х", **{"опори": [{"уривок": "х"}]})'), {2}),
        '16067-типове-значення-параметра': (
            писач.replace('опори=None', 'опори=({"уривок": "мінус десять"},)'), {2}),
        '16068-переприсвоєння-поля': (
            писач.replace('        записати(', '        поле = "смуга_погоди"\n        записати('), {2}),
        '16042-другий-прямий-писач': (
            писач + '\n\ndef додати(паспорт):\n'
            '    паспорт["картка"]["смуга_погоди"] = {"опори": [{"уривок": "мінус десять"}]}\n', {2}),
    }
    for назва, (текст, очікувані) in випадки.items():
        дерево = {'джерела/ш_поля.py': прилад._ЧИТАЧ_ОПОР, 'джерела/ш_запис.py': текст}
        результат = прилад._прогін(дерево, {'опори_читач': очікувані})
        print(назва + ': ' + результат[0][0])


if __name__ == "__main__":
    main()
