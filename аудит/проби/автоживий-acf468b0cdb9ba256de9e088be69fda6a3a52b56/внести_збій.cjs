/* Тільки сцена ж7: вручну змінює дані каталогу в пам'яті Pyodide, зберігає
   видимі відмови, відновлює дані й передає керування звичайному стенду. */
const fs = require('fs'), path = require('path');
module.exports = async function(стор) {
  const вихід = path.resolve(process.env.ZNIMKY, '..');
  const записи = [];
  for (const поле of ['каблук_см', 'сезон_тканини']) {
    global.__ж7_внесення = поле;
    const код = `
import json, feed as Ф, міст_пакет as М, profile as ПР
if '_цілий_прогін_ж7' not in globals():
    _цілий_прогін_ж7 = Ф.прогін_кроками
_поле_ж7 = ${JSON.stringify(поле)}
_зміни_ж7 = []
def _битий_прогін_ж7(*а, **к):
    пр = yield from _цілий_прогін_ж7(*а, **к)
    for р in пр['каталог']:
        if _поле_ж7 == 'каблук_см':
            if р.get('слот') != 'взуття' or ПР.сенсорний_збіг('підбори', р):
                continue
        elif р.get('слот') not in ('верх', 'низ', 'сукня', 'комплект') or not р.get('ціна'):
            continue
        _зміни_ж7.append({'id': р.get('id'), 'поле': _поле_ж7, 'до': р.get(_поле_ж7), 'після': 'битий запис'})
        р[_поле_ж7] = 'битий запис'
    return пр
Ф.прогін_кроками = _битий_прогін_ж7
М.КЕШ_ПАКЕТА.clear()
json.dumps({'поле': _поле_ж7})
`;
    await стор.evaluate(код => приладМостуП({}, код), код);
    await стор.evaluate(() => зібратиОбразиП());
    const дані = await стор.evaluate(async () => ({
      статус: (document.getElementById('зб-статус') || {}).textContent,
      діагноз: ЗБ.діагноз, готово: ЗБ.готово, успіх: ЗБ.успіх,
      паспорт: ПАСПОРТ_П,
      зміни: JSON.parse(await приладМостуП({}, 'json.dumps(_зміни_ж7, ensure_ascii=False)')),
    }));
    записи.push({поле, ...дані});
    await стор.screenshot({path:path.join(вихід, 'знімки', 'збій_' + поле + '.png'),fullPage:true});
    fs.writeFileSync(path.join(вихід,'пошкоджені_поля.json'),JSON.stringify(записи,null,2));
    console.log('ВНЕСЕНИЙ ЗБІЙ:', поле, JSON.stringify({статус:дані.статус, діагноз:дані.діагноз, змінено:дані.зміни.length}));
    await стор.evaluate(() => приладМостуП({}, 'Ф.прогін_кроками = _цілий_прогін_ж7\nМ.КЕШ_ПАКЕТА.clear()\n"Каталог відновлено"'));
    if (!дані.зміни.length || дані.успіх || !дані.статус || !дані.діагноз.some(р => /sensory_limit_unreadable|fabric_band_unreadable/.test(р)))
      throw Error('Сцена ж7: очікуваного видимого збою для ' + поле + ' не доведено; див. пошкоджені_поля.json');
  }
  global.__ж7_внесення = null;
  const доказ = await стор.evaluate(() => приладМостуП({}, `
_р_ж7 = {'id': 'проба-ж7-човники', 'слот': 'взуття', 'тип': 'човники', 'каблук_см': 'битий запис'}
json.dumps({'річ': _р_ж7, 'вето': ПР.сенсорний_збіг('підбори', _р_ж7)}, ensure_ascii=False)
`));
  fs.writeFileSync(path.join(вихід,'незалежний_доказ_підбора.json'), доказ);
  console.log('КАТАЛОГ ВІДНОВЛЕНО; звичайний стенд виконає повне збирання.');
};
