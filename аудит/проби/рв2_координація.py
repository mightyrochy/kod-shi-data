# РВ-6 З-5 (рядок 5 дошки): `ВЕРДИКТ_V1.набір.координація` оголошено в схемі й не
# мало жодного писача — `coordination.координація()` кладе вирок K-COMP-01 у
# `знахідки` ОБРАЗУ, а не в таблицю набору. Друкує факт на живому шляху: скільки
# образів у наборі, скільки рядків координації і які ранги.
# Запуск: python3 аудит/проби/рв2_координація.py
import sys, os, json, tempfile
ДЖ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "джерела")
sys.path.insert(0, ДЖ); os.chdir(ДЖ)
import bridge as B, feed as Ф, протокол as P

вх = json.load(open("стенд_вх.json", encoding="utf-8"))
d0 = dict(вх, каталог=Ф.каталог_на_диску("каталог_brief.xml"), варіантів=10,
          кеш_кольорів=os.path.join(tempfile.gettempdir(), "кеш_проби_коорд.json"))
пул = json.loads(json.loads(B.виклик("запити", json.dumps(d0, ensure_ascii=False)))["руки"]["1"])["пул"]
н = lambda сл, i: пул[сл][i % len(пул[сл])]["н"]
образи = [dict(ід="о%d" % (i + 1), підпис="проба %d" % (i + 1),
               речі=[н("сукня", i), н("взуття", i), н("сумка", i), н("каблучка", i)])
          for i in range(5)]
в = json.loads(B.виклик("від_моделі", json.dumps(
    dict(d0, текст_моделі=json.dumps(dict(версія="1", образи=образи), ensure_ascii=False)),
    ensure_ascii=False)))
набір = (в["вердикт"].get("набір") or {})
коорд = набір.get("координація")
print("образів у вердикті: %d · рядків набір.координація: %s"
      % (len(в["вердикт"]["образи"]), "НЕМА ПОЛЯ" if коорд is None else len(коорд)))
print("координація:", json.dumps(коорд, ensure_ascii=False))
print("K-COMP-01 у знахідках о1:",
      [z.get("сила_нп") for z in в["вердикт"]["образи"][0]["знахідки"] if z.get("правило") == "K-COMP-01"])
print("поле в схемі:", "координація" in P.ВЕРДИКТ_V1["поля"]["набір"]["поля"],
      "· помилок схеми вердикту:", len(P.перевірити(P.СХЕМИ["ВЕРДИКТ_V1"], в["вердикт"])))
