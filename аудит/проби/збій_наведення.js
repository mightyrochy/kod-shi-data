    /* відновлення: воркер більше не закривається, той самий вибір ще раз — міст піднімається наново */
    await стор.evaluate(() => { Worker.prototype.postMessage = window.__пост_воркера; });
    await плитка(до.макіяж === 'помітний' ? 'помітний' : 'яскравий');
