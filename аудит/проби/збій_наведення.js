  /* ── kadr: після карток ── */
  async function кадр(стор, з){
    const поклали = await покласти(стор, 'портрет', null);
    крок('портрет покладено', поклали);
    await стор.evaluate(() => { режим('профіль'); відкритиАркушПрофілю('др-блок'); });
    if (!(await стор.locator('#кд-м').isVisible({timeout: 10000}).catch(() => false)))
      return вердикт(false, 'не виміряно: повзунка кадру #кд-м не видно після портрета');
    const до = {пам_ять: await стор.evaluate(() => ({...КАДР})), запис: await сирийЗапис(стор, 'кв', 'кадр'), ...(await екран(стор))};
    крок('до', до);
    await стор.evaluate(() => {
      const о = IDBObjectStore.prototype.put;
      window.__пут = о;
      IDBObjectStore.prototype.put = function(значення, ключ){
        const р = о.apply(this, arguments);
        if (ключ === 'кадр') this.transaction.abort();
        return р;
      };
    });
    const тягнути = async частка => {
      const б = await стор.locator('#кд-м').boundingBox();
      await стор.mouse.move(б.x + б.width * 0.5, б.y + б.height / 2);
      await стор.mouse.down();
      await стор.mouse.move(б.x + б.width * частка, б.y + б.height / 2, {steps: 8});
      await стор.mouse.up();
      await пауза(1500);
    };
    await тягнути(0.8);
    const збій = {пам_ять: await стор.evaluate(() => ({...КАДР})), запис: await сирийЗапис(стор, 'кв', 'кадр'), ...(await екран(стор, '#збій-панель'))};
    крок('запис кадру скасовано', збій);
    await з.знімок('zbij_kadr_1_ne_zbereglos', null, true, true);
    await стор.evaluate(() => { IDBObjectStore.prototype.put = window.__пут; });
    const зрозуміло = стор.getByRole('button', {name: 'Зрозуміло', exact: true});
    if (await зрозуміло.isVisible().catch(() => false)) await зрозуміло.click();
    await тягнути(0.3);
    const після = {пам_ять: await стор.evaluate(() => ({...КАДР})), запис: await сирийЗапис(стор, 'кв', 'кадр'), ...(await екран(стор))};
    крок('після відновлення', після);
    await з.знімок('zbij_kadr_2_vidnovleno', null, true, true);
    await стор.click('#аркуш-готово').catch(() => {});
    const видно = збій.тривога.some(т => /Не збереглось/.test(т));
    const розійшлось = JSON.stringify(збій.запис) !== JSON.stringify(збій.пам_ять);
    const відн = JSON.stringify(після.запис) === JSON.stringify(після.пам_ять) && !після.тривога.some(т => /Не збереглось/.test(т));
    вердикт(видно && розійшлось && відн, 'при скасованому записі: ' + (видно ? 'видно «' + збій.тривога.join(' / ').slice(0, 160) + '»' : 'тривоги нема')
      + '; запис ' + JSON.stringify(збій.запис) + ' ≠ на екрані ' + JSON.stringify(збій.пам_ять) + '; після відновлення запис = екран: ' + відн);
  }

