    /* `стор.evaluate` стенда чекає тиші моста, а мертвий воркер її не дасть до сторожа виклику (300 с): посеред
       чекання дивимось сирим `evaluate` сторінки — те, що жінка бачить ці 300 с */
    const сир = стор.показПідЧасМоста ? {evaluate: стор.показПідЧасМоста.evaluate} : стор;
    const т0 = Date.now();
    const зупинено = await чекати(сир, () => !!window.__помади_зупинено, null, 120000);
