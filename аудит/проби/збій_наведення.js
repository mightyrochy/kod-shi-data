    const за = await чекати(сир, () => !!ПОМАДИ_ЗБІЙ_П || !!ПОМАДИ_П, null, 420000);
    const від_дотику = Math.round((Date.now() - т0) / 1000);
    const збій = await екран(стор, '#сц-губи-стан');
    крок('після сторожа виклику', {за_с: за, від_дотику_с: від_дотику, збій_помад: await стор.evaluate(() => ПОМАДИ_ЗБІЙ_П && {вид: ПОМАДИ_ЗБІЙ_П.вид,
      причина: String((ПОМАДИ_ЗБІЙ_П.причина && ПОМАДИ_ЗБІЙ_П.причина.message) || ПОМАДИ_ЗБІЙ_П.причина).slice(0, 200)}), ...збій});
    await з.знімок('zbij_pomady_2_zbii', null, true, true);
    /* перемальовування: аркуш закрито й відкрито знову */
    await стор.click('#аркуш-готово').catch(() => {});
    if (!(await стор.locator('[data-редактор="ред-макіяж"]').isVisible())) await стор.click('#сц-ще').catch(() => {});
    await стор.click('[data-редактор="ред-макіяж"]').catch(() => {});
