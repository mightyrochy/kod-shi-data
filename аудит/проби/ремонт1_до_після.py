"""РЕМОНТ-1 (рядки 4290, 4291): ДО/ПІСЛЯ правки ремонту на тих самих входах заміру ГГ-1, бік продукту (`з_гг1`). Без
мосту й моделі — лише записи `аудит/проби/гг1_повтор_ремонту.py` (BOKY=з_гг1) двох робочих копій.
  python3 аудит/проби/ремонт1_до_після.py <тека ДО> <тека ПІСЛЯ>
Що вважати кращим — у шапці PR РЕМОНТ-1: п'ятірка не о1…о5 підряд і з образами о6–о10, образи відповіді = «chosen»;
обривів, `"answer": {`, ехо даних і «done» над зауваженнями — менше; секунд на виклик — не більше (п.21); з блокером —
не більше (лише разом із рядком 4350: речі входу без кольору)."""
import gzip, json, glob, os, re, statistics as С, sys, collections as K

ЕХО = re.compile(r'\n\s{0,4}"(fixes|not_run_everywhere|set|showcase|verdict|case|day)"\s*:')
ключ_опори = lambda z: (z.get("правило"), next((з.get("code") for з in z.get("заяви") or [] if isinstance(з, dict)), None))
речі = lambda z: {у.get("річ") for у in z.get("учасники") or []} or set(z.get("речі") or [])
# Лічба, що береться з поля, якого запис боку не має (ДО: образів після ремонту й «chosen» нема), друкується «—», не 0.
ПОЛЕ_ЛІЧБИ = {"з блокером": "образи_після", "є «chosen»": "обрано", "образи = «chosen»": "обрано", "опор пережило": "після"}


def бік(тека):
    вих = {}
    for ф in glob.glob(os.path.join(тека, "сирі", "*.json.gz")):
        з = json.load(gzip.open(ф, "rt", encoding="utf-8"))
        if not з["з_гг1"].get("збій"):
            вих[з["ключ"]] = з["з_гг1"]
    return вих


def лічба(х):
    Л = K.Counter(); с, сек = [], []
    for к, поле in ПОЛЕ_ЛІЧБИ.items():
        Л["є поле: " + к] += поле in х
    п = json.loads(х["промпт"]); гейти = {z.get("id") for о in п.get("verdict") or [] for z in о.get("findings") or [] if z.get("register") == "gate"}
    for в in х["виклики"]:
        т = в["текст"]; с.append(len(т)); сек.append(в["с"]); Л["викликів"] += 1; Л["обрізано"] += в["обрізано"]
        Л['"answer": {'] += bool(re.search(r'"answer"\s*:\s*\{', т)); Л["ехо даних промпту"] += bool(ЕХО.search(т))
        for ід in re.findall(r'"finding"\s*:\s*"([^"]+)"', т):
            Л["done над гейтом" if ід in гейти else "done над зауваженням"] += 1
    т = х["виклики"][-1]["текст"]
    # ІД, ЯКІ НАПИСАЛА МОДЕЛЬ (`ід_моделі`), а не `номер` мосту: його міст роздає за позицією у відповіді, о1…о5
    лат = lambda сп: [str(і).replace("о", "o") for і in сп]
    обр = лат(х.get("ід_моделі") or [])[:len(х.get("образи_після") or []) or None]
    if "ід_моделі" not in х:        # запис заміру ГГ-1 (до РЕМОНТ-1): ід — з тексту образів, без блокерів
        т0 = т[т.find('"outfits"'):]; м = ЕХО.search(т0)
        обр = list(dict.fromkeys(re.findall(r'"id"\s*:\s*"(o\d+)"', т0[:м.start()] if м else т0)))[:5]
    вибр = лат(х.get("обрано") or [])
    Л["п'ятірка = о1…оN підряд"] += обр == ["o%d" % і for і in range(1, len(обр) + 1)]
    Л["образів о6–о10 у відповіді"] += sum(int(о[1:]) > 5 for о in обр if о[1:].isdigit())
    Л["є «chosen»"] += bool(вибр); Л["образи = «chosen»"] += bool(вибр) and вибр == обр
    Л["образів після"] += len(обр); Л["з блокером"] += sum(о["блокує"] for о in х.get("образи_після") or [])
    оп = [(ід, z) for ід, оо in х["до"] for z in оо]
    Л["опор"] += len(оп)
    Л["опор пережило"] += sum(any(ключ_опори(x) == ключ_опори(z) and речі(x) & речі(z) for _, оо in х.get("після") or [] for x in оо) for _, z in оп)
    return Л, с, сек


до, піс = бік(sys.argv[1]), бік(sys.argv[2])
спільні = sorted(set(до) & set(піс))
print("пар без збою на обох: %d (ДО %d, ПІСЛЯ %d)" % (len(спільні), len(до), len(піс)))
Р = {}
for ім, б in (("ДО", до), ("ПІСЛЯ", піс)):
    Л, с, сек = K.Counter(), [], []
    for к in спільні:
        л, с1, с2 = лічба(б[к]); Л += л; с += с1; сек += с2
    Р[ім] = (Л, С.median(с) if с else 0, С.median(сек) if сек else 0)
for к in ("п'ятірка = о1…оN підряд", "образів о6–о10 у відповіді", "є «chosen»", "образи = «chosen»", "викликів", "обрізано",
          '"answer": {', "ехо даних промпту", "done над гейтом", "done над зауваженням", "образів після", "з блокером",
          "опор", "опор пережило"):
    знач = lambda б: Р[б][0][к] if к not in ПОЛЕ_ЛІЧБИ or Р[б][0]["є поле: " + к] else "—"
    print("  %-34s ДО %-6s ПІСЛЯ %s" % (к, знач("ДО"), знач("ПІСЛЯ")))
print("  %-34s ДО %-6.0f ПІСЛЯ %.0f" % ("символів відповіді, медіана", Р["ДО"][1], Р["ПІСЛЯ"][1]))
print("  %-34s ДО %-6.0f ПІСЛЯ %.0f" % ("секунд на виклик, медіана", Р["ДО"][2], Р["ПІСЛЯ"][2]))
