def спец_продукт(F, src=None, схема="нейтрали+акцент", слоти=СЛ4, **kw):
    """`спец_слоти`, як їх складає `міст_пакет` (рядки 1755, 2075–2095) для однієї схеми."""
    с = PS.специфікація(F, схема, list(слоти), source=src or "model_hex", **kw)
    сп = dict(с.get("слоти") or {},
              **({"_поверхні": "великі", "_сім_ї": с.get("сім_ї_схеми") or []} if с.get("поверхні") == "великі" else {}),
              _схема=с.get("схема"), _палітра=с.get("палітра_практична"),
              _контраст=(с.get("палітра_практична") or {}).get("контраст_рівень"), _намір=kw.get("intent"))
    return сп, с


def s1п(речі, src=None, схема="нейтрали+акцент", сценарій=None, кандидати=None, повний=False, спец_kw=None, **проф):
    F, T, _ = профіль(src, **проф)
    к = [кат(str(і), *р[:3], **(р[3] if len(р) > 3 else {})) for і, р in enumerate(речі, 1)]
    спец, _ = спец_продукт(F, src, схема, слоти=[r["слот"] for r in к], **(спец_kw or {}))
    кн = None
    if кандидати:
        кн = {}
        for r in к:
            кн.setdefault(r["слот"], []).append(dict(r, **кандидати.get(r["id"], {})))
    о = PL.перевірити_від_моделі([r["id"] for r in к], F, к, T, dict(СЦЕН, **(сценарій or {})),
                                 спец_слоти=спец, кандидати=кн)
    з = [(_ід(x), x.get("сила")) for x in о["знахідки"]]
    return (з, о, спец) if повний else з


