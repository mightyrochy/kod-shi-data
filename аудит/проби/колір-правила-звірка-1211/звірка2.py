def ід_є(з, правило, сили=None):
    """Точний ID (без «будь-якої K-PAL-*»), сила не «питання»/«без_входу»/«утримано», або з `сили`."""
    for і, с in з:
        if і == правило and (с in сили if сили else с not in ("питання", "без_входу", "утримано")):
            return True
    return False


def сили(з, правило):
    return sorted({str(с) for і, с in з if і == правило})


