def hx(L, C, h):
    return cs.hex_з_lab((L, C * math.cos(math.radians(h)), C * math.sin(math.radians(h))))


def LCh(hexv):
    return tuple(round(x, 1) for x in cs.lch(cs.hx(hexv)))


