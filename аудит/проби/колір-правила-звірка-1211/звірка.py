def є(з, правило, сила=None):
    """Чи спрацювало правило: знахідка з цим ID (крім «питання»/«утримано»/«без_входу», якщо сила не задана)."""
    for і, с in з:
        if і == правило or і.startswith(правило + "-"):
            if сила is None and с not in ("питання", "утримано", "без_входу"):
                return True
            if сила is not None and (с == сила or str(с).startswith(сила)):
                return True
    return False


