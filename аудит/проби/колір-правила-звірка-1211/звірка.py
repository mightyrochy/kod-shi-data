# ── 1. корпус ──────────────────────────────────────────────────────────────────
def корпус():
    out = {}
    for f in sorted(glob.glob("тема-*.md")):
        for n, l in enumerate(open(f, encoding="utf-8"), 1):
            s = l.strip()
            for m in ID.finditer(l):
                i = m.group(1)
                д = re.match(r"^(>\s*)?(#+\s*|[-*]\s*\*\*|\*\*)\s*" + re.escape(i) + r"\b", s)
                з = out.setdefault(i, dict(означення=None, згадки=0))
                з["згадки"] += 1
                if д and not з["означення"]:
                    з["означення"] = "%s:%d" % (f, n)
    return out


# ── 2. код ─────────────────────────────────────────────────────────────────────
def код():
    місця = {}
    for f in sorted(glob.glob("*.py")):
        if f.startswith(("тест_", "gate_", "батарея_", "audit_")) or f in ("реєстр_політика.py", "rule_genus.py"):
            continue
        try:
            t = ast.parse(open(f, encoding="utf-8").read())
        except SyntaxError:
            continue
        док = set()
        for в in ast.walk(t):
            if isinstance(в, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                if в.body and isinstance(в.body[0], ast.Expr) and isinstance(getattr(в.body[0], "value", None), ast.Constant):
                    док.add(id(в.body[0].value))
        for в in ast.walk(t):
            if isinstance(в, ast.Constant) and isinstance(в.value, str) and id(в) not in док:
                for m in ID.finditer(в.value):
                    місця.setdefault(m.group(1), set()).add(f)
    return {k: sorted(v) for k, v in місця.items()}


