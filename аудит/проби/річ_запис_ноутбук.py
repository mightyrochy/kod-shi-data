"""Дописати п.3 Річ-запис-речі сторінками чотирьох крамниць за Cloudflare із жнив 5.3 ноутбука (31.10).

Запуск із кореня на ноутбуці: python -X utf8 аудит/проби/річ_запис_ноутбук.py [ЖНИВА]
ЖНИВА — тека жнив 5.3 ноутбука (типово ~/.cache/liusterko/harvest-5.3-claude), лише читання, без мережі.
Для кожної з 12 адрес вибірки (зерно 11658) цих крамниць, а за відсутності — для кандидатів-замінників
30.10 (`кандидати.json`, наступні за порядком) береться збережена відповідь HTTP 200 жнив
(`проходи/<крамниця>/черга.sqlite3`, SHA256 звіряється). Пише ТЕКА=річ_запис_каталог_2026_10_30/ноутбук_31_10:
html/ нових сторінок, вибірка_п3.json (144 сторінки 30.10 + нові), очі_п3.json (30.10 + очі_ноутбук.json),
джерела.json (звідки кожна сторінка чи причина, чому її нема) і api_tm_beart.json — записи tm-beart проти
відповіді Woo Store API жнив, з якої їх складено (сторінки HTML у жнивах нема). Далі в ТЕЦІ —
річ_запис_блок.py і річ_запис_частки.py без змін.
"""
import hashlib
import html
import json
from pathlib import Path
import re
import sqlite3
import sys

from річ_запис_каталог import записати, стиснути

КОРІНЬ = Path(__file__).resolve().parents[2]
ПРОБА = КОРІНЬ / 'аудит/проби/річ_запис_каталог_2026_10_30'
ТЕКА = ПРОБА / 'ноутбук_31_10'
КРАМНИЦІ = ['attico.ua', 'intimo.com.ua', 'theoriginals.com.ua', 'tm-beart.com']


def читати(шлях):
    """Прочитати JSON."""
    return json.loads(шлях.read_text(encoding='utf-8'))


def відповідь(жнива, крамниця, url):
    """Остання збережена відповідь HTTP 200 жнив на цю адресу або None."""
    база = жнива / 'проходи' / крамниця / 'черга.sqlite3'
    if not база.is_file():
        return None
    з = sqlite3.connect(база.as_uri() + '?mode=ro', uri=True)
    ряд = з.execute('SELECT час,код,sha256,файл,кінцева FROM відповіді WHERE url=? AND код=200 ORDER BY ід DESC LIMIT 1',
                    (url,)).fetchone()
    з.close()
    if not ряд or not (база.parent / ряд[3]).is_file():
        return None
    дані = (база.parent / ряд[3]).read_bytes()
    if hashlib.sha256(дані).hexdigest() != ряд[2]:
        raise ValueError('Не збігається SHA256 збереженої відповіді: ' + ряд[3])
    return dict(час=ряд[0], sha256=ряд[2], кінцева=ряд[4], дані=дані)


def стан_крамниці(жнива, крамниця):
    """Що є в жнивах про крамницю: кількість збережених відповідей 200 або чому нема."""
    тека = жнива / 'проходи' / крамниця
    база = тека / 'черга.sqlite3'
    if база.is_file():
        з = sqlite3.connect(база.as_uri() + '?mode=ro', uri=True)
        ч = з.execute('SELECT count(*) FROM відповіді WHERE код=200').fetchone()[0]
        з.close()
        return f'черга жнив: відповідей HTTP 200 — {ч}'
    return 'черги сторінок нема; файли проходу: ' + ', '.join(sorted(п.name for п in тека.iterdir())) if тека.is_dir() else 'проходу нема'


def текст(т):
    """HTML у звичайний текст для звірки з API."""
    return ' '.join(html.unescape(re.sub(r'<[^>]+>', ' ', т or '')).split())


def звірка_api(жнива, записи):
    """Записи tm-beart проти товарів Woo Store API, з яких їх складено в жнивах 5.3."""
    товари = {}
    for ф in sorted((жнива / 'проходи/tm-beart.com/json_сторінки').glob('*.json'), key=lambda п: int(п.stem)):
        for т in читати(ф)['речі']:
            товари[т['permalink'].rstrip('/')] = dict(сторінка_api=ф.name, **т)
    результат = []
    for з in записи:
        т = товари.get(з['url'].rstrip('/'))
        if т is None:
            результат.append(dict(id=з['id'], url=з['url'], api=None))
            continue
        опис_api = текст(т.get('description'))
        атрибути = {а['name']: [в['name'] for в in а.get('terms', [])] for а in т.get('attributes', [])}
        результат.append(dict(id=з['id'], url=з['url'], сторінка_api=т['сторінка_api'],
            назва=dict(запис=з['назва'], api=т['name'], збіг=з['назва'] == т['name']),
            опис=dict(запис=з['опис'], api=опис_api[:600], запис_у_api=bool(з['опис']) and ' '.join(з['опис'].split())[:200] in опис_api),
            склад=dict(запис=з['склад'], атрибути_api=атрибути),
            розділ=dict(запис=з['розділ'], api=[к['name'] for к in т.get('categories', [])])))
    return результат


def main():
    """Зібрати нові сторінки й вхід частки 52 крамниць."""
    жнива = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / '.cache/liusterko/harvest-5.3-claude'
    вибірка = [р for р in читати(ПРОБА / 'вибірка.json') if р['крамниця'] in КРАМНИЦІ]
    кандидати = {к['замість']: к['кандидати'] for к in читати(ПРОБА / 'кандидати.json')}
    (ТЕКА / 'html').mkdir(parents=True, exist_ok=True)
    старі = читати(ПРОБА / 'вибірка_п3.json')
    нові, джерела = [], []
    for р in sorted(вибірка, key=lambda р: (р['крамниця'], р['url'])):
        for к in [р] + кандидати.get(р['url'], []):
            в = відповідь(жнива, р['крамниця'], к['url'])
            if в:
                break
        if not в:
            джерела.append(dict(id=р['id'], url=р['url'], крамниця=р['крамниця'], сторінка=None,
                причина='у жнивах 5.3 ноутбука нема збереженої сторінки цієї адреси й кандидатів 30.10; ' + стан_крамниці(жнива, р['крамниця'])))
            continue
        файл = 'html/' + hashlib.sha256(к['url'].encode()).hexdigest()[:16] + '.html.gz'
        стиснути(ТЕКА / файл, в['дані'])
        нові.append(dict(id=к['id'], url=к['url'], крамниця=р['крамниця'], назва=к['назва'], опис=к['опис'],
            склад=к['склад'], розділ=к['розділ'], файл=файл, замість=None if к is р else р['url'],
            джерело_сторінки=f'збережена відповідь HTTP 200 жнив 5.3 ноутбука ({в["час"]})'))
        джерела.append(dict(id=к['id'], url=к['url'], крамниця=р['крамниця'], сторінка=файл, час_жнив=в['час'],
            sha256_відповіді=в['sha256'], кінцева=в['кінцева'], замість=None if к is р else р['url']))
    вхід = [dict(х, файл='../' + х['файл']) for х in старі] + нові
    записати(ТЕКА / 'вибірка_п3.json', sorted(вхід, key=lambda х: х['id']))
    записати(ТЕКА / 'очі_п3.json', читати(ПРОБА / 'очі_п3.json') + читати(ТЕКА / 'очі_ноутбук.json'))
    записати(ТЕКА / 'джерела.json', джерела)
    записати(ТЕКА / 'api_tm_beart.json', звірка_api(жнива, [р for р in вибірка if р['крамниця'] == 'tm-beart.com']))
    print('нових сторінок:', len(нові), '; без сторінки:', sum(д['сторінка'] is None for д in джерела), '; усього:', len(вхід))


if __name__ == '__main__':
    main()
