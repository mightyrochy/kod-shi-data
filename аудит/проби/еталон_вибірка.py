# -*- coding: utf-8 -*-
# Еталон правди про речі каталогу (наряд РЗ-Е, рядок 404): вибірка 60 речей і знімок чотирьох джерел про кожну.
# 40 випадкових по слотах (сід 17, квота слота ∝ √розміру — дрібні слоти прикрас теж потрапляють) + 20 «мовчазних»
# (у тексті крамниці лише назва, колір, розміри, категорія, бренд, артикул, сезон — без опису й описових полів).
# Фото — тим самим вибором, що на картці (`фід_фото.кадри_речі`, як `огляд_крамниць.py`), перші 4 кадри: коли перший
# не показує річ, суддя дивиться наступні. Аркуші для судді — ЛИШЕ фото (суд наосліп, без відповідей джерел).
# Запуск: python3 аудит/проби/еталон_вибірка.py <розбір.json> <тека>   (PIL, curl, мережа; ~2 хв)
#   пише <тека>/вибірка.json (id, кадри, текст крамниці, джерела (б)(в)(г) сирими) і <тека>/сліпі/NN.jpg
import sys, os, json, re, math, random, hashlib, subprocess, collections, concurrent.futures as cf
РОЗБІР, ТЕКА = [os.path.abspath(а) for а in sys.argv[1:3]]
Д = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'джерела')
sys.path.insert(0, Д); os.chdir(Д); os.makedirs(ТЕКА + '/сліпі', exist_ok=True); os.makedirs('/tmp/фото_огляд', exist_ok=True)
import feed as F; F.каталог_на_диску('каталог_повний.xml')
import фід_каталог as ФК, фід_фото as ФФ, каталог_розбір as КР
from PIL import Image, ImageDraw, ImageFont
кат = ФК._прочитати_каталог('каталог_повний.xml', 0)['каталог']
_оф = F.читати_yml('каталог_повний.xml')[0]
_зб, _спільні, _хости = F.читати_збагачення(), ФФ._спільні_фото(_оф), ФФ._хости_крамниць(_оф)
_за_ід = {o['id']: o for o in _оф}
розбір = json.load(open(РОЗБІР, encoding='utf-8'))
def кадри(x):
    o = _за_ід[x['id']]
    return ФФ.кадри_речі(o, _спільні.get(o.get('магазин')) or {}, _хости,
                        (x.get('кадр_кольору') or {}).get('кадр') or (_зб.get(o.get('id')) or {}).get('фото'))[:4]
# «Мовчазна» річ: жодного поля крамниці понад назву, колір, розміри й мірки (числа), категорію, бренд, артикул, сезон.
НЕОПИСОВІ = re.compile(r'^~?(категорія_магазину|категорії|колір|color|розмір\w*|size|оберіть розмір|сезон|артикул|'
                       r'теги|бренд|стан|опис стану|тип|модель|виробник\W*|наявність|стать|int|код( товар\w)?|sku|'
                       r'країна виробництва|правила догляду|рейтинг|ціна|зріст_моделі_см|ріст|параметри моделі|'
                       r'розмір на моделі|обхвати_моделі|таблиця_мірок|назва_сира|напівобхват \w+|довжина по спині|ширина( плечей)?|'
                       r'довжина рукава|довжина устілки|eu/it|свотч_\w+|[\d/x\-a-z]+)$')   # мірки й свотч — числа, не слова
def мовчазна(o):
    опис = re.sub(r'(?i)опис:?', '', re.sub('<[^>]+>', ' ', o.get('опис') or '')).strip()
    return len(опис) < 15 and all(НЕОПИСОВІ.match(к) for к in КР.поля_крамниці(o))
rnd = random.Random(17)
придатні = [x for x in кат if x['id'] in розбір and кадри(x)]
по = collections.defaultdict(list)
for x in придатні: по[x['слот']].append(x)
вага = {с: math.sqrt(len(xs)) for с, xs in по.items()}
квота = {с: int(40 * в / sum(вага.values())) for с, в in вага.items()}
for с in sorted(вага, key=lambda с: -(40 * вага[с] / sum(вага.values())) % 1)[:40 - sum(квота.values())]:
    квота[с] += 1
def шлях(u): return '/tmp/фото_огляд/' + hashlib.md5(u.encode()).hexdigest() + '.img'
def тягти(u):
    if not os.path.exists(шлях(u)) or os.path.getsize(шлях(u)) == 0:
        subprocess.run(['curl', '-sS', '-L', '-m', '40', '-o', шлях(u), u], capture_output=True)
def видно(x):
    """Кадр картки відкривається як фото. attico.ua з хмари віддає сторінку Cloudflare замість фото (3 речі
    першого прогону) — таку річ суддя не побачить, її заміняє наступна в тому самому сідованому порядку."""
    тягти(кадри(x)[0])
    try:
        Image.open(шлях(кадри(x)[0])).verify(); return True
    except Exception:                                  # noqa: BLE001 — не фото: річ не судиться, лічба нижче
        відкинуто.append(x['id']); return False
відкинуто = []
запас = random.Random(17)                              # заміни — окремим генератором: вибір лишається тим самим
def взяти(xs, к):
    за_ід = sorted(xs, key=lambda x: x['id']); вибрані = rnd.sample(за_ід, к)
    решта = [x for x in запас.sample(за_ід, len(за_ід)) if x not in вибрані]
    вих = []
    for x in вибрані:
        вих.append(x if видно(x) else next(з for з in решта if з not in вибрані + вих and видно(з)))
    return вих
вибір = [(x, 'слот') for с in sorted(по) for x in взяти(по[с], квота[с])]
взято = {x['id'] for x, _ in вибір}
тихі = sorted((x for x in придатні if мовчазна(_за_ід[x['id']]) and x['id'] not in взято), key=lambda x: x['id'])
вибір += [(x, 'мовчазна') for x in взяти(тихі, 20)]
with cf.ThreadPoolExecutor(12) as ex: list(ex.map(тягти, [u for x, _ in вибір for u in кадри(x)]))
ПОЛЯ_Б = ('слот', 'тип', 'набір', 'довжина_рівень', 'довжина_джерело', 'рукав_слово', 'крій', 'крій_джерело', 'волокно',
          'волокно_джерело', 'матеріал', 'матеріал_фото', 'візерунок', 'візерунок_джерело', 'колір_назва', 'колір_назва_джерело',
          'колір_назва_фото', 'колір_джерело', 'блиск', 'блиск_джерело', 'метал', 'деталі_крою')
записи = []
for н, (x, група) in enumerate(вибір, 1):
    код, збої = КР.що_каже_код(_за_ід[x['id']])
    записи.append({'н': н, 'id': x['id'], 'група': група, 'кадри': кадри(x), 'текст': КР.вхід(_за_ід[x['id']]),
                   'б': {к: x.get(к) for к in ПОЛЯ_Б}, 'б_словники': код, 'в': _зб.get(x['id']), 'г': розбір[x['id']]})
json.dump(записи, open(ТЕКА + '/вибірка.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
шр = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', 20)
for п in range(0, len(записи), 2):                     # дві речі на аркуш, по 4 кадри; лише фото й номер
    арк = Image.new('RGB', (4 * 360, 2 * 510), 'white'); д = ImageDraw.Draw(арк)
    for р, з in enumerate(записи[п:п + 2]):
        д.text((6, р * 510 + 4), '#%d' % з['н'], fill='red', font=шр)
        for к, u in enumerate(з['кадри']):
            try:
                im = Image.open(шлях(u)).convert('RGB'); im.thumbnail((352, 480)); арк.paste(im, (к * 360 + 4, р * 510 + 28))
            except Exception as е:                    # noqa: BLE001 — биті кадри видно на аркуші
                д.text((к * 360 + 10, р * 510 + 60), 'кадр не відкрився: %s' % type(е).__name__, fill='red', font=шр)
    арк.save('%s/сліпі/%02d.jpg' % (ТЕКА, п // 2 + 1), quality=85)
print('речей %d · по слотах %s · мовчазних кандидатів %d · кадр не фото, замінено: %s' % (len(записи), dict(collections.Counter(
    з['б']['слот'] for з in записи if з['група'] == 'слот')), len(тихі), відкинуто))
