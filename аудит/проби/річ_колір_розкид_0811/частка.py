"""Мірило кроку (рішення менеджера 08.11, п.2): частка кадрів з кодом з виміру ДО → ПІСЛЯ і причина спаду.

ДО — `дельта.json.gz` гілки даних (43dd34ad), ПІСЛЯ — той самий кадр з `перевимір.json.gz`. Сукупності:
вся дельта (2536 кадрів), кадри, що змінили колір (сукупність приймання 08.11: придатний hex ≠ старого,
фото в маніфесті), уражена частина (поправка ×≥1,10 чи «тон невідомо»). Кадр, якого хмара не
відтворила (інша маска, SAM), — окремо: його ПІСЛЯ не виміряно. Пише `зберегли_код.tsv` — уражені кадри,
що зберегли код з виміру (сукупність мірила очима), — поруч із першим файлом перевиміру.

    python3 -I частка.py <тека даних> <перевимір.json.gz> [<перевимір_SAM.json.gz> …]
"""
import collections, csv, gzip, json, sys
from pathlib import Path

тека = Path(sys.argv[1])
перевимір = dict(записи={}, звірка={})
for шлях in sys.argv[2:]:                      # хмара (ATR) і ноутбук (SAM) — ті самі ключі, пізніший файл переважає
    ч = json.load(gzip.open(шлях, "rt", encoding="utf-8"))
    for ід, кк in ч["записи"].items():
        перевимір["записи"][ід] = {в["файл"]: в for в in перевимір["записи"].get(ід, []) + кк}.values()
    перевимір["звірка"].update(ч["звірка"])
дельта = json.load(gzip.open(тека / "дельта.json.gz", "rt", encoding="utf-8"))
до = json.load(gzip.open(тека / "кадри_ДО.json.gz", "rt", encoding="utf-8"))["записи"]
фото = {(м["id"], м["файл"], м["url"]): м["фото"] for м in дельта["маніфест"]}
нові = {(ід, в["файл"]): в for ід, кк in перевимір["записи"].items() for в in кк}
зв = перевимір["звірка"]
л, причини, коди, зберегли = collections.Counter(), collections.Counter(), collections.Counter(), []
for ід, кадри in sorted(дельта["записи"].items()):
    старі = {в["файл"]: в for в in до.get(ід, [])}
    for в in кадри:
        код_до = в.get("колір_тип") == "вимір" and в.get("придатна") is True
        змінив = код_до and в.get("hex") and в["hex"] != старі.get(в["файл"], {}).get("hex") and (ід, в["файл"], в["url"]) in фото
        з = зв.get("%s|%s" % (ід, в["файл"]), {})
        н = нові.get((ід, в["файл"]))
        for с in ["вся дельта"] + (["змінили колір"] if змінив else []) + (["уражені"] if з.get("уражений") else []):
            л[с, "кадрів"] += 1
            л[с, "ДО"] += код_до
            if код_до and not з.get("відтворено"):
                л[с, "не відтворено"] += 1
                continue
            л[с, "ПІСЛЯ"] += bool(н and н["колір_тип"] == "вимір") if код_до else 0
            if код_до and н and н["колір_тип"] != "вимір":
                причини[с, з.get("причина")] += 1
                коди[с, в.get("слово")] += 1
        if з.get("уражений") and з.get("відтворено") and н and н["колір_тип"] == "вимір":
            зберегли.append(dict(id=ід, файл=в["файл"], фото=фото.get((ід, в["файл"], в["url"]), ""), hex=н["hex"],
                                 код=н["слово"], код_до=в.get("слово"), змінив_колір=bool(змінив)))
for с in ("вся дельта", "змінили колір", "уражені"):
    к = л[с, "кадрів"]
    print("%s: кадрів %d; з кодом з виміру ДО %d (%.1f%%) → ПІСЛЯ %d (%.1f%%); не відтворено хмарою %d" % (
        с, к, л[с, "ДО"], 100 * л[с, "ДО"] / к, л[с, "ПІСЛЯ"], 100 * л[с, "ПІСЛЯ"] / к, л[с, "не відтворено"]))
    print("  причина спаду:", dict(sorted(((п, n) for (сс, п), n in причини.items() if сс == с), key=lambda x: -x[1])))
    print("  код ДО у знятих:", dict(sorted(((п, n) for (сс, п), n in коди.items() if сс == с), key=lambda x: -x[1])[:12]))
with open(Path(sys.argv[2]).parent / "зберегли_код.tsv", "w", encoding="utf-8", newline="") as ф:
    п = csv.DictWriter(ф, fieldnames=list(зберегли[0]) if зберегли else ["id"], delimiter="\t")
    п.writeheader(); п.writerows(зберегли)
print("уражені, що зберегли код з виміру: кадрів %d, речей %d" % (len(зберегли), len({з["id"] for з in зберегли})))
# не відтворені: маска інша (SAM у хмарі → запасна) чи та сама маска з іншим hex (ATR процесора проти відеокарти)
нв = collections.Counter("SAM → %s" % з["маска"] if з["маска_до"] != з["маска"] else "та сама маска, інший hex"
                         for з in зв.values() if not з["відтворено"])
print("не відтворено:", dict(нв), "; з них з кодом ПІСЛЯ:",
      sum(1 for з in зв.values() if not з["відтворено"] and з["код"]))
# код ПІСЛЯ — найтісніше вікно, що вміщає весь розкид; воно може бути ширшим за вікно точки (слово ДО)
зм = collections.Counter((з["код_до"], з["код"]) for з in зв.values() if з["відтворено"] and з["код"] and з["код"] != з["код_до"])
print("зберегли код, але інше слово, ніж ДО: %d; часті:" % sum(зм.values()), dict(зм.most_common(8)))
