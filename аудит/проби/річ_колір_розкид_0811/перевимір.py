"""Перевимір уражених кадрів дельти перезбору (43dd34ad) записувачем з розкидом коду (рішення менеджера 08.11).

Уражені — кадри з придатним виміром, де поправка тла ×≥1,10 чи «тон невідомо» (наряд). Решти придатних
вимірів записані поля не вирішують: U тону відомого й множники каналів поправки в дельту не записано
(лише середній множник у `чому`), тож перевиміряно всі придатні виміри, а `уражений` — позначка у звірці. Маска — той самий
`жнива_маски.маска_речі` (ATR на процесорі; SAM у хмарі нема — такий кадр позначено, не підмінено),
вимір — `жнива_колір.поверхня_фото`, запис — `жнива_кадри.записати_вимір`. Звірка: головний сегмент
нового виміру має той самий hex, що записав ноутбук, і та сама маска — інакше кадр «не відтворено».

    python3 -I перевимір.py <тека даних з фото/ і дельта.json.gz> <вихід.json.gz> [--процесів 3] [--маска SAM]
"""
import argparse, gzip, json, os, re, subprocess, sys, time
from multiprocessing import Pool
from pathlib import Path

КОРІНЬ = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(КОРІНЬ / "джерела"))
os.chdir(КОРІНЬ / "джерела")


def поправка(в):
    м = re.search(r"експозиція ×([\d.]+)", в.get("чому") or "")
    return float(м.group(1)) if м else None


def уражений(в):
    """Чи кадр під правилом кроку: придатний вимір з поправкою ×≥1,10 чи з «тон невідомо»."""
    if в.get("колір_тип") != "вимір" or not в.get("придатна"):
        return False
    return (поправка(в) or 1.0) >= 1.10 or "тон невідомо" in ((в.get("вимір") or {}).get("чому") or "")


def причина(сег, множники):
    """Чому код з виміру знято: «тло» (без поправки код є), «хрома» (без C ± U код є), «обидва»."""
    import surface as S
    lab, U = tuple(сег["lab"]), сег["хрома"][1]
    без_тла = S.код_розкиду(lab, U, None)[0]
    без_хроми = S.код_розкиду(lab, 0.0, множники)[0]
    return "тло" if без_тла and not без_хроми else "хрома" if без_хроми and not без_тла else (
        "обидва" if not без_тла and not без_хроми else "лише разом")


def один(завдання):
    ід, слот, старий, фото = завдання
    os.environ.setdefault("OMP_NUM_THREADS", "1")
    import жнива_колір as ЖК, жнива_кадри as Ж
    вимір = ЖК.поверхня_фото(фото, слот)
    новий = Ж.записати_вимір({к: старий[к] for к in ("файл", "url", "клас") if к in старий}, вимір)
    п = вимір["поверхня"] or {}
    сег = (п.get("сегменти") or [None])[0]
    гол = (новий.get("вимір") or {}).get("сегменти") or [[None, None, None]]
    з = dict(маска_до=старий.get("маска"), маска=новий.get("маска"), hex_до=старий.get("hex"), hex_сегмента=гол[0][2],
             код_до=старий.get("слово"), код=новий.get("слово") if новий["колір_тип"] == "вимір" else None,
             поправка=п.get("поправка"), хрома=сег and сег["хрома"], тон_невідомо=bool(сег and сег["тон"] is None))
    з["уражений"] = уражений(старий)
    з["відтворено"] = з["маска_до"] == з["маска"] and з["hex_до"] == з["hex_сегмента"]
    if з["код"] is None and сег:
        з["причина"] = причина(сег, п.get("множники"))
    return ід, новий, з


def головна():
    ар = argparse.ArgumentParser()
    ар.add_argument("тека"); ар.add_argument("вихід"); ар.add_argument("--процесів", type=int, default=3)
    ар.add_argument("--ліміт", type=int, default=None)
    ар.add_argument("--маска", default=None, help="лише кадри з цією записаною маскою (SAM — на ноутбуці)")
    а = ар.parse_args()
    тека = Path(а.тека)
    дельта = json.load(gzip.open(тека / "дельта.json.gz", "rt", encoding="utf-8"))
    фото = {(м["id"], м["файл"]): str(тека / м["фото"]) for м in дельта["маніфест"]}
    import feed as Ф, жнива_промпти as ЖП
    офери = {о["id"]: о for о in Ф.читати_yml(Ф.каталог_на_диску())[0]}
    завдання = [(ід, ЖП.тип_речі(офери[ід])[1], в, фото[(ід, в["файл"])])
                for ід, кадри in sorted(дельта["записи"].items()) for в in кадри
                if в.get("колір_тип") == "вимір" and в.get("придатна") and (ід, в["файл"]) in фото
                and а.маска in (None, в.get("маска"))][:а.ліміт]
    print("придатних вимірів: %d, з них уражених %d" % (len(завдання), sum(уражений(з[2]) for з in завдання)),
          flush=True)
    вих = dict(мета=dict(код=subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip(),
                        дані="claude/Річ-колір-вимір 43dd34adee5bf462c70cbdc9f01719da7250719e",
                        команда=sys.argv, почато_utc=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())),
               записи={}, звірка={})
    # Частини — по рядку на кадр: вбитий за пам'яттю процес (16 ГБ хмари, ATR росте) губить лише свій кадр,
    # а повторний запуск з тим самим виходом бере зроблене й доміряє решту.
    частини = Path(а.вихід + ".частини.jsonl")
    зроблено = {}
    if частини.exists():
        for р in частини.read_text(encoding="utf-8").splitlines():
            ід, новий, з = json.loads(р)
            зроблено["%s|%s" % (ід, новий["файл"])] = (ід, новий, з)
    решта = [з for з in завдання if "%s|%s" % (з[0], з[2]["файл"]) not in зроблено]
    print("зроблено раніше: %d, решта: %d" % (len(зроблено), len(решта)), flush=True)
    with Pool(а.процесів, maxtasksperchild=8) as пул, частини.open("a", encoding="utf-8") as ф:
        for н, (ід, новий, з) in enumerate(пул.imap_unordered(один, решта, chunksize=1), 1):
            ф.write(json.dumps([ід, новий, з], ensure_ascii=False) + "\n"); ф.flush()
            зроблено["%s|%s" % (ід, новий["файл"])] = (ід, новий, з)
            if н % 50 == 0:
                print("%d/%d" % (н, len(решта)), flush=True)
    for ключ, (ід, новий, з) in sorted(зроблено.items()):
        вих["записи"].setdefault(ід, []).append(новий)
        вих["звірка"][ключ] = з
    вих["мета"]["скінчено_utc"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    with gzip.open(а.вихід, "wt", encoding="utf-8") as ф:
        json.dump(вих, ф, ensure_ascii=False)


if __name__ == "__main__":
    головна()
