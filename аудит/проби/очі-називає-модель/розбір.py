#!/usr/bin/env python3
"""Таблиця «портрет — видно — модель — сім'я коду» з сирих відповідей `виклик.py` (без моделі, без моста).

Відповідь читає реєстр продукту (`міст_вхід.прийняти_колір`); очі профілю — `міст_вхід.features` на прочитаному (як
міст: портрет без виміру очей); сім'я, яку бачить модель палітри, — `вибір_палітри._особа` (`person.eyes.family`) і
клас риси `face_features.класи`. «Видно» — колір райдужок на вирізках кадрів рамками
`набір-фото-жінок/прогін.js` (огляд виконавця 26.11, збігається з задумом маніфесту). Сім'я вірна, коли
`person.eyes.family` — у множині `ВІРНІ` для видимого кольору: зелені — green (оливково-зелені — ще olive),
блакитні — blue, карі — brown (код продукту), а за сім'ями палітри ДО — orange чи red (буре на колі художника — RO–O).
Запуск (з кореня): python3 аудит/проби/очі-називає-модель/розбір.py <тека> <прохід> [<прохід>…]"""
import json, sys
from pathlib import Path

КОРІНЬ = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(КОРІНЬ / "джерела"))
import міст_вхід as МВ, вибір_палітри as ВП, face_features as ОЗ  # noqa: E402

ВИДНО = {"ж1": "сіро-зелені", "ж2": "оливково-зелені", "ж3": "сіро-блакитні", "ж4": "темно-карі",
         "ж7": "блакитні", "ж8": "карі"}
ВІРНІ = {"ж1": {"green"}, "ж2": {"green", "olive"}, "ж3": {"blue"}, "ж4": {"brown", "orange", "red"},
         "ж7": {"blue"}, "ж8": {"brown", "orange", "red"}}


def рядок(текст):
    из = МВ.прийняти_колір(текст)
    if из["стан"] != "готово":
        return dict(стан=из["стан"])
    d = dict(шкіра=из["шкіра"], волосся=из["волосся"], очі=из["очі"], очі_кільце=из["кільце"],
             **({"колір_очей": из["колір_очей"]} if из.get("колір_очей") else {}))
    F = МВ.features(d)[0]
    особа = ВП._особа(F, {"особа": {}, "палітри": None})
    оч = особа.get("eyes") or {}
    return dict(hex=из["очі"], код=из.get("колір_очей"), family=оч.get("family"), source=оч.get("source"),
                status=оч.get("status"), yellow_blue=оч.get("yellow_blue"), клас=ОЗ.класи(F).get("очі"))


if __name__ == "__main__":
    тека, проходи = Path(sys.argv[1]), sys.argv[2:]
    вірних = {}
    print("| портрет | видно | прохід | hex моделі | код моделі | person.eyes.family | джерело | yellow_blue | клас `face_features.класи` | вірно |")
    print("|---|---|---|---|---|---|---|---|---|---|")
    for ж in ВИДНО:
        for п in проходи:
            р = рядок((тека / п / f"{ж}.txt").read_text(encoding="utf-8"))
            ок = р.get("family") in ВІРНІ[ж]
            вірних[п] = вірних.get(п, 0) + ок
            print(f"| {ж} | {ВИДНО[ж]} | {п} | {р.get('hex')} | {р.get('код') or '—'} | {р.get('family')} | "
                  f"{р.get('source')} | {р.get('yellow_blue')} | {р.get('клас')} | {'так' if ок else 'ні'} |")
    print()
    print("вірно: " + ", ".join(f"прохід {п} — {в} з {len(ВИДНО)}" for п, в in вірних.items()))
