"""РВ-3 · «рука жінки важить над паспортом» (показ) проти «правда — в її словах» (промпт).
Жінка сказала в чаті «побачення», потім рукою поставила плитку «робота» → виклик 0 перезбирає
паспорт з усією розмовою. Запуск із теки `джерела`: python3 ../аудит/проби/рв3_рука_проти_слів.py"""
import json
import bridge as B, pipeline as PL

сц = dict(нагода="робота", місце="офіс_креативний", година=19, темп_c=12)    # плитка після її дотику
п_досі = dict(подія="побачення в ресторані", нагода="побачення", місце="ресторан_районний")
історія = [dict(хто="людина", текст="побачення в ресторані о сьомій"),
           dict(хто="ші", текст="Зрозуміла: побачення в закладі о 19:00.")]
пр = PL.промпт_паспорта(сц, "побачення в ресторані о сьомій", історія=історія, паспорт=п_досі)
о = json.loads(пр)      # повідомлення збирача (25.09): поля входу — ключами
for к in ("обрано", "змінено_рукою", "паспорт_досі", "розмова"):
    print("  промпт «%s»:" % к, json.dumps(о.get(к), ensure_ascii=False)[:150])
print("  промпт каже, що плитку змінено рукою ПІСЛЯ розмови:", bool(о.get("змінено_рукою")))
# модель, слухняна до «правда — в її словах», повертає побачення; розбір іде тим самим
# шляхом, що й у показі (`паспортПоРозмовіП`: та сама база з паспортом досі — і в промпт, і в розбір)
база = dict(сценарій=сц, вимоги="", паспорт=п_досі, історія=історія)
п = json.loads(B.виклик("паспорт", json.dumps(dict(база, json_моделі=json.dumps(
    dict(п_досі, відповідь_людині="Побачення в ресторані."), ensure_ascii=False)), ensure_ascii=False)))["паспорт"]
print("  паспорт після виклику 0: нагода=%s (плитка була «%s»), джерело_полів=%s"
      % (п["нагода"], сц["нагода"], п.get("джерело_полів")))
