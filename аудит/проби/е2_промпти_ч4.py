"""Порівнює частину 4 з базою на каталозі й записаному збагаченні, без моделі.

Запуск із кореня: python аудит/проби/е2_промпти_ч4.py <SHA бази>.
Тотожний читач записів не доводить поведінки моделі після зміни промпту.
"""
import gzip
import json
from pathlib import Path
import subprocess
import sys
import types

КОРІНЬ = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРІНЬ / "джерела"))
import feed as Ф
import жнива_збагачення as Ж
import приміряння as П
import уважний_вибір as У


def попередня(назва):
    """Завантажує лише призначений модуль бази, без окремої копії репозиторію."""
    шлях = "джерела/" + назва + ".py"
    текст = subprocess.check_output(["git", "show", sys.argv[1] + ":" + шлях], cwd=КОРІНЬ)
    модуль = types.ModuleType("до_" + назва)
    модуль.__file__ = str(КОРІНЬ / шлях)
    exec(compile(текст, модуль.__file__, "exec"), модуль.__dict__)
    return модуль


def головна():
    """Міряє змінені входи й збереження даних та схем на однакових записах."""
    ж, п, у = map(попередня, ("жнива_збагачення", "приміряння", "уважний_вибір"))
    каталог, _ = Ф.читати_yml(str(КОРІНЬ / "каталог_повний.xml"), показ=False)
    типи = {Ж.тип_для_промпту(р)[0] for р in каталог}
    різниці = {len(ж._промпт(т)) - len(Ж._промпт(т)) for т in типи}
    assert різниці and min(різниці) > 0 and ж.ШАБЛОН == Ж.ШАБЛОН
    with gzip.open(КОРІНЬ / "джерела/каталог_збагачення.json.gz", "rt", encoding="utf-8") as вхід:
        записи = json.load(вхід)
    розбіжності = sum(ж.нормалізувати(р) != Ж.нормалізувати(р) for р in записи.values())
    assert not розбіжності
    print(f"Каталог: {len(каталог)} речей, {len(типи)} типів; промпти коротші на {sorted(різниці)} символів.")
    print(f"Збережене збагачення: {len(записи)} записів, розбіжностей читача {розбіжності}; шаблон незмінний.")
    for назва in ("ОЦІНКА", "ТУРНІР"):
        дані = {"items" if назва == "ОЦІНКА" else "groups": {"dress-1": [{"n": "1·01"}]}}
        до = json.loads(у._запит(getattr(у, назва), дані, 1, "assess", "probe", "1")["текст"])
        після = json.loads(У._запит(getattr(У, назва), дані, 1, "assess", "probe", "1")["текст"])
        розміри = [len(json.dumps(д, ensure_ascii=False)) for д in (до, після)]
        assert розміри[1] < розміри[0]
        до["task"].pop("role"); після["task"].pop("role")
        assert до == після
        print(f"{назва}: {розміри}; крім ролі, дані, правила й схема тотожні.")
    for власна in (False, True):
        for макіяж in (None, {"рівень": "помітний", "губи": "#b02e40"}):
            річ = {"слот": "сукня", "назва": "dress", "власна": власна}
            for повтор in (False, True):
                аргументи = ([річ], [річ], макіяж, ["belt at waist"], повтор)
                до, після = [json.loads(м.промпт(*аргументи)) for м in (п, П)]
                assert len(json.dumps(після)) < len(json.dumps(до))
                assert {к: в for к, в in до.items() if к != "task"} == {
                    к: в for к, в in після.items() if к != "task"}
    print("Приміряння: 8 комбінацій власності, макіяжу й повтору; дані тотожні, запити коротші.")


if __name__ == "__main__":
    головна()
