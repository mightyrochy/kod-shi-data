#!/bin/bash
# Н2 7f5: продовження поза фоновим завданням інструмента (його межа 30 хв). Чекає кінця с3 (PID 17592), далі решта.
B=/tmp/n2/сцени7f5; S=/tmp/n2/stor7f5
while kill -0 17592 2>/dev/null; do sleep 5; done
sleep 3
grep -q "кінець типове/с3" $B/хід.txt || echo "$(date -u +%FT%TZ) кінець типове/с3 (node 17592 завершився; рядок час.txt: $(tail -1 $B/типове/с3/час.txt))" >> $B/хід.txt
run(){ echo "$(date -u +%FT%TZ) старт $1/$2" >> $B/хід.txt
  bash /tmp/n2/сцена_живо.sh $B/$1/$2 "$3" /tmp/n2/жінки/$4 $S
  echo "$(date -u +%FT%TZ) кінець $1/$2 $(tail -1 $B/$1/$2/час.txt)" >> $B/хід.txt; }
unset VIKNO_N2
run типове с5 "я гостя на весіллі сестри в серпні, церемонія надворі о 16:00, потім ресторан" с5_оксана.json
run типове с8 "на вулиці мінус десять і сніг, йду на роботу пішки 20 хвилин" с8_юлія.json
export VIKNO_N2=1000000
run вікно1м с3 "на роботу пішки, увесь день дощ, взуття — замшеві чоботи" с3_оксана.json
run вікно1м с5 "я гостя на весіллі сестри в серпні, церемонія надворі о 16:00, потім ресторан" с5_оксана.json
run вікно1м с8 "на вулиці мінус десять і сніг, йду на роботу пішки 20 хвилин" с8_юлія.json
echo "$(date -u +%FT%TZ) УСЕ" >> $B/хід.txt
