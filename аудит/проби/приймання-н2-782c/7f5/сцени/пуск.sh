#!/bin/bash
# Н2 7f5: с3/с5/с8, спершу без #вікно= (основний), потім #вікно=1000000 (вікно CLI, не Cloudflare)
B=/tmp/n2/сцени7f5; S=/tmp/n2/stor7f5
run(){ # $1 режим $2 сцена $3 слова $4 жінка
  echo "$(date -u +%FT%TZ) старт $1/$2" >> $B/хід.txt
  bash /tmp/n2/сцена_живо.sh $B/$1/$2 "$3" /tmp/n2/жінки/$4 $S
  echo "$(date -u +%FT%TZ) кінець $1/$2 $(tail -1 $B/$1/$2/час.txt)" >> $B/хід.txt
}
for M in типове вікно1м; do
  if [ $M = вікно1м ]; then export VIKNO_N2=1000000; else unset VIKNO_N2; fi
  run $M с3 "на роботу пішки, увесь день дощ, взуття — замшеві чоботи" с3_оксана.json
  run $M с5 "я гостя на весіллі сестри в серпні, церемонія надворі о 16:00, потім ресторан" с5_оксана.json
  run $M с8 "на вулиці мінус десять і сніг, йду на роботу пішки 20 хвилин" с8_юлія.json
done
echo "$(date -u +%FT%TZ) УСЕ" >> $B/хід.txt
