def scene_status(scene):
    directory = OUT / scene
    result = directory / 'результат.json'
    if scene == INTERRUPTED:
        return 'перервано сесією після фіксації блокера; не результат продукту'
    if not result.exists():
        return 'не запущено після фіксації блокера'
    data = json.loads(result.read_text(encoding='utf-8'))
    if 'rc' not in data:
        return 'обрив приладу на межі 1800 с; запис незавершений'
    return f"стенд закінчився, rc={data['rc']}; автоматичний доказ не пройшов"


