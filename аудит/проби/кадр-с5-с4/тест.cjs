const assert = require('node:assert/strict');
const {execFileSync} = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const {test} = require('node:test');
const vm = require('node:vm');
const фікстура = require('./фікстура.json');

const корінь = path.resolve(__dirname, '../../..');
function код(файл, функції){
  const джерело = process.env.KADR_TEST_BASE
    ? execFileSync('git', ['show', process.env.KADR_TEST_BASE + ':' + файл], {cwd:корінь, encoding:'utf8'})
    : fs.readFileSync(path.join(корінь, файл), 'utf8');
  return функції.map(імʼя => {
    const збіг = джерело.match(new RegExp('^function ' + імʼя + '\\([\\s\\S]*?^}', 'm'));
    assert.ok(збіг, імʼя);
    return збіг[0];
  }).join('\n');
}

const {річ:туфлі, у_виклику:кадриТуфель} = фікстура.с5;
const [кадрТуфель, кадрСумки] = кадриТуфель;
const {річ:сережка, у_виклику:[кадрФутляра]} = фікстура.с4;
const збіги = ціль => (ціль.className || '').split(' ');
const нічого = () => {};

function середовище(картка){
  const адреси = [];
  function ел(tagName, className, textContent){
    return {tagName, className, textContent, dataset:{}, style:{}, children:[],
      set src(url){ адреси.push(url); this.джерело = url; },
      appendChild(child){ child.parent = this; this.children.push(child); return child; },
      replaceWith(child){ this.parent.children.splice(this.parent.children.indexOf(this), 1, child); }};
  }
  const п = vm.createContext({
    П:{картки:[картка]}, ел, елЖінціП:ел,
    document:{createElement:ел}, ЧИСЛА:['Перший'], НАПИСИ_БЕЗ_ШАРУ_П:new Set(), ВЕЛИКІ_СЛОТИ:[],
    закріпитиСвоїШаруП:нічого, своїЕкрануП:нічого, текстЖінціП:нічого, розміткаЖінціП:нічого,
    замінюванаРічП:() => false, крамниця:() => '', грн:() => '', людською:() => ['', []],
    рядокПідПереліком:() => '', НЕ_ЦЯ_П:new Set(), чекаютьРозгортанняП:() => false,
    вердиктДотикиЙПолеП:нічого,
  });
  vm.runInContext(код('джерела/показ/картки.js', ['кадриРечі']), п);
  vm.runInContext(код('джерела/показ/екран/картка.js', ['підставитиКадр', 'рендерКартку']), п);
  // Силует визначено в одну стрічку, без окремої кінцевої дужки.
  п.силуетКадру = () => ел('i', 'арка');
  return {п, адреси};
}

function відхилення(позначки, речі, доставки, блоки = речі.flatMap(р => р.фото.map(url => ({
  type:'image', source:{type:'url', url},
})))){
  const п = vm.createContext({});
  vm.runInContext(код('джерела/показ/збирання_руки.js', ['відхиленняКадрівОпису']), п);
  return JSON.parse(JSON.stringify(п.відхиленняКадрівОпису(позначки, {речі}, блоки, доставки)));
}

function картка(речі, поля){
  const {п, адреси} = середовище({речі, ...поля});
  const дерево = п.рендерКартку(0);
  const знайти = (вузол, клас) => [вузол, ...вузол.children.flatMap(д => знайти(д, клас))]
    .filter(н => збіги(н).includes(клас));
  return {дерево, адреси, знайти};
}

const однаДоставка = (надіслано, дійшло = надіслано) => [{надіслано, дійшло}];
const вхідТуфель = [{id:туфлі.id, фото:кадриТуфель}];
const точнаСумка = {id:туфлі.id, url:кадрСумки};
// Архівний вимір невідомий. Це контроль із заданим чинним доказом для точної URL туфель.
const перевіреніТуфлі = {...туфлі, кадр_виміру:{стан:'measured'}, клас_кадру:'ціла_річ'};

function силуети(результат, id){
  const {дерево, знайти} = результат;
  const плитка = знайти(дерево, 'ф').find(вузол => вузол.dataset.id === id);
  assert.ok(плитка, 'у колажі збережений слот речі');
  assert.equal(знайти(плитка, 'арка').length, 1, 'силует у колажі');
  assert.equal(знайти(дерево, 'річ').length, 1);
  assert.equal(знайти(знайти(дерево, 'річ')[0], 'арка').length, 1, 'силует у мініатюрі');
}

test('архівний с5: позначка про річ лишає обидва силуети без жодного src', () => {
  const результат = картка([туфлі], {фото_не_ті:фікстура.с5.фото_не_ті});
  assert.deepEqual(результат.адреси, []);
  силуети(результат, туфлі.id);
});

test('два кадри у відповідному виклику с5: позначка про річ явно неоднозначна', () => {
  const докази = відхилення(фікстура.с5.фото_не_ті, вхідТуфель, однаДоставка(2));
  assert.deepEqual(докази, [{id:туфлі.id, адреси:[], неоднозначно:true}]);
  const результат = картка([туфлі], {відхилення_кадрів:докази});
  assert.deepEqual(результат.адреси, []);
  силуети(результат, туфлі.id);
});

test('точне відхилення сумки: туфлі видно в колажі та мініатюрі за обох порядків галереї', () => {
  const докази = відхилення([точнаСумка], вхідТуфель, однаДоставка(2));
  assert.deepEqual(докази, [{id:туфлі.id, адреси:[кадрСумки], неоднозначно:false}]);
  for (const фото_усі of [туфлі.фото_усі, туфлі.фото_усі.slice().reverse()]){
    const результат = картка([{...перевіреніТуфлі, фото_усі}], {відхилення_кадрів:докази});
    assert.deepEqual(результат.адреси, [кадрТуфель, кадрТуфель]);
  }
});

test('помилка перевіреного кадру: спроби обмежені тією самою URL до силуетів', () => {
  const докази = відхилення([точнаСумка], вхідТуфель, однаДоставка(2));
  const результат = картка([перевіреніТуфлі], {відхилення_кадрів:докази});
  const {дерево, знайти} = результат;
  const плитка = знайти(дерево, 'ф')[0];
  const фото = [...плитка.children.flatMap(в => в.tagName === 'a' ? в.children : [в]),
                ...знайти(дерево, 'мініатюра')].filter(в => в.tagName === 'img');
  assert.equal(фото.length, 2);
  for (const img of фото){ img.onerror(); img.onerror(); }
  assert.deepEqual(результат.адреси, Array(4).fill(кадрТуфель));
  силуети(результат, туфлі.id);
});

test('с4: задане відхилення єдиної URL футляра зберігає слот без запиту фото', () => {
  const вхід = [{id:сережка.id, фото:[кадрФутляра]}];
  const докази = відхилення([{id:сережка.id, url:кадрФутляра}], вхід, однаДоставка(1));
  const результат = картка([сережка], {відхилення_кадрів:докази});
  assert.deepEqual(результат.адреси, []);
  силуети(результат, сережка.id);
});

