test('точне відхилення не зачіпає інший ID навіть із тією самою URL', () => {
  const докази = відхилення([точнаСумка], вхідТуфель, однаДоставка(2));
  const інша = {...сережка, фото:кадрСумки, фото_усі:[кадрСумки]};
  const результат = картка([перевіреніТуфлі, інша], {відхилення_кадрів:докази});
  assert.deepEqual(результат.адреси, [кадрТуфель, кадрСумки, кадрТуфель, кадрСумки]);
});

test('часткова доставка, клієнтське обрізання та перетин завершень не визначають URL', () => {
  for (const доставки of [однаДоставка(2, 1), однаДоставка(1), [...однаДоставка(2), ...однаДоставка(1)]]){
    for (const позначка of [туфлі.id, точнаСумка]){
      const докази = відхилення([позначка], вхідТуфель, доставки);
      assert.deepEqual(докази, [{id:туфлі.id, адреси:[], неоднозначно:true}]);
      const результат = картка([туфлі], {відхилення_кадрів:докази});
      assert.deepEqual(результат.адреси, []);
      силуети(результат, туфлі.id);
    }
  }
});

