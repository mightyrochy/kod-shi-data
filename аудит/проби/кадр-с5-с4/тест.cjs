function джерелоКоду(файл){
  return process.env.KADR_TEST_BASE
    ? execFileSync('git', ['show', process.env.KADR_TEST_BASE + ':' + файл], {cwd:корінь, encoding:'utf8'})
    : fs.readFileSync(path.join(корінь, файл), 'utf8');
}

function код(файл, функції){
  const джерело = джерелоКоду(файл);
  return функції.map(імʼя => {
    const збіг = джерело.match(new RegExp('^(?:(?:async )?function ' + імʼя
      + '|const ' + імʼя + ' = async )\\([\\s\\S]*?^};?$', 'm'));
    assert.ok(збіг, імʼя);
    return збіг[0];
  }).join('\n');
}

