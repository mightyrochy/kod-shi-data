#!/usr/bin/env python3
"""Тестовий прогін наряду `Збирання-рука-1-два-кроки`: таблиця ДО → ПІСЛЯ і пари руки 1 «наосліп».

python3 -I аудит/проби/Збирання-рука-1-два-кроки/пари.py <тека ДО> <тека ПІСЛЯ> <куди>  (з кореня)

Тека — вихід `аудит/проби/драйвер_хмарного_прогону.py` (`<сцена>__<прохід>/`). З `лог.txt` — секунди до першої
картки (рядок «рука 1: картка за X с») і виклики руки 1 за кроком; з `вердикти.txt` — картка руки 1 (речі й текст).
Пише `<куди>/ПАРИ.md` (у кожній парі образи «А» і «Б» у випадковому порядку, сід 2011) і `<куди>/ключ_пар.txt`
(котрий із них ДО). Нових викликів моделі нема."""
import glob, json, os, random, re, sys

до, після, куди = sys.argv[1:4]


def прохід(д):
    лог = open(os.path.join(д, 'лог.txt'), encoding='utf-8').read()
    м = re.search(r'рука 1: картка за ([\d.]+) с', лог)
    рез = json.load(open(os.path.join(д, 'результат.json'), encoding='utf-8'))
    try:
        в = json.load(open(os.path.join(д, 'вердикти.txt'), encoding='utf-8'))
        к = next(v for v in в['прогони'][0]['вердикти'] if str(v['рука']) == '1')
    except Exception:
        к = {}
    кроки = [в.get('крок') for в in ((к.get('етапи') or {}).get('виклики') or [])]
    return dict(сек=float(м.group(1)) if м else None, викликів=к.get('викликів'), кроки=кроки, rc=рез.get('rc'),
                вибір_складання='choice_from_assembly=yes' in лог,
                речі=[р.get('назва') for р in (к.get('речі_образу') or [])], опис=(к.get('опис') or '').strip())


рядки, пари = [], []
for д in sorted(glob.glob(os.path.join(до, '*__*'))):
    ім = os.path.basename(д)
    п = os.path.join(після, ім)
    if not all(os.path.exists(os.path.join(т, 'результат.json')) for т in (д, п)):
        continue
    а, б = прохід(д), прохід(п)
    рядки.append('| %s | %s → %s | %s → %s | %s → %s | %s → %s |' % (
        ім, а['сек'], б['сек'], а['викликів'], б['викликів'], ' '.join(map(str, а['кроки'])),
        ' '.join(map(str, б['кроки'])), а['rc'], б['rc']))
    пари.append((ім, а, б))

print('| сцена__прохід | рука 1: с до картки | викликів картки | кроки руки 1 | rc стенда |')
print('|---|---|---|---|---|')
print('\n'.join(рядки))

рнд = random.Random(2011)
os.makedirs(куди, exist_ok=True)
ключ, текст = [], ['# Пари руки 1 наосліп: ДО і ПІСЛЯ тих самих сцен', '',
                   'У кожній парі — перша картка (рука 1) того самого запиту двома збірками; котра ДО — у `ключ_пар.txt`.',
                   'Оцінка: котрий образ краще служить її нагоді й словам («А», «Б» чи «рівні»), і чи має хоч один ваду, яку',
                   'жінка побачить «як людина».', '']
for ім, а, б in пари:
    перший_до = рнд.random() < 0.5
    А, Б = (а, б) if перший_до else (б, а)
    ключ.append('%s: А=%s' % (ім, 'ДО' if перший_до else 'ПІСЛЯ'))
    текст.append('## ' + ім)
    for мітка, о in (('А', А), ('Б', Б)):
        текст += ['', '**%s.** Речі: %s' % (мітка, '; '.join(map(str, о['речі'])) or '—'), '', о['опис'] or '—']
    текст.append('')
open(os.path.join(куди, 'ПАРИ.md'), 'w', encoding='utf-8').write('\n'.join(текст))
open(os.path.join(куди, 'ключ_пар.txt'), 'w', encoding='utf-8').write('\n'.join(ключ) + '\n')
