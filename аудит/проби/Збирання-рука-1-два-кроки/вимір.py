#!/usr/bin/env python3
"""Крок 1 наряду `Збирання-рука-1-два-кроки`: вимір ланцюга руки 1 на записах прогону через міст (#4488).

python3 -I аудит/проби/Збирання-рука-1-два-кроки/вимір.py [тека=аудит/проби/Живий-через-міст]  (з кореня репозиторію)

На кожен прохід: секунди кожного виклику руки 1 (запис кроку `етапи.виклики` у verdykty-*.json, секунди — з обміну
моста `стенд/службове/<с>/обміни.jsonl` за тим самим текстом відповіді), «Зібрати»→перша картка (`хід.md`, як
`стенд/числа.py`); чи ремонт змінив обраний образ (склад образу з тим самим id у складанні й на картці); чи вибір
узяв образ, який код ставив першим (`selection_policy.ключ_образу` над образами вибору: блокери, гейти, речі, id).
Нових викликів моделі нема."""
import collections, datetime as D, glob, json, os, re, sys

тека = sys.argv[1] if len(sys.argv) > 1 else 'аудит/проби/Живий-через-міст'


def текст_відповіді(x):
    try:
        в = json.loads(x.get('відповідь') or '')
    except Exception:
        return ''
    return ''.join(б.get('text', '') for б in (в.get('content') or []) if isinstance(б, dict))


def гейти(о):
    return [з for з in (о.get('знахідки') or []) if isinstance(з, dict) and з.get('регістр') == 'гейт'
            and not з.get('свідомий')]


def ключ(о):
    """`selection_policy.ключ_образу` за записом образу кроку: (недопустимий, гейт, гейтів, блокерів, −речей, id)."""
    бл, г = о.get('блокери') or [], гейти(о)
    return (bool(бл or г), bool(г), len(г), len(бл), -len(о.get('ід') or []), str(о.get('номер') or ''))


def склад(о):
    return frozenset(str(і).split('/')[0] for і in (о.get('ід') or []))


def моменти_ходу(шлях):
    t = open(шлях, encoding='utf-8').read()
    st = [(int(m[1]), D.datetime.fromisoformat(m[2].replace('Z', '+00:00')), m[3], m[4])
          for m in re.finditer(r'### (\d+) · (\S+) · прохід (\d) · [^\n]*\n(.*?)(?=\n### |\Z)', t, re.S)]
    вих = {}
    for p in sorted({x[2] for x in st}):
        S = [x for x in st if x[2] == p]
        ck = [x for x in S if 'Зібрати образи»' in x[3] and 'дія скрипта' in x[3]]
        n = [x for x in S if ck and x[0] > ck[0][0] and 'Твої образи.' in x[3]]
        вих[int(p)] = (ck[0][1] if ck else None, n[0][1] if n else None)
    return вих


рядки, лічба = [], collections.Counter()
сек_кроків = collections.defaultdict(list)
for сц in sorted(glob.glob(os.path.join(тека, 'с*_*'))):
    с = os.path.basename(сц)
    обм = os.path.join(тека, 'стенд', 'службове', с, 'обміни.jsonl')
    if not os.path.exists(обм):
        continue
    обміни = [json.loads(л) for л in open(обм, encoding='utf-8')]
    за_текстом = collections.defaultdict(list)
    for x in обміни:
        за_текстом[текст_відповіді(x).strip()].append(x)
    ходи = моменти_ходу(os.path.join(сц, 'хід.md'))
    прогони = []
    for вф in sorted(glob.glob(os.path.join(сц, 'verdykty-*.json'))):
        прогони += json.load(open(вф, encoding='utf-8'))['прогони']
    for прохід, пр in enumerate(прогони, 1):
        в1 = [в for в in пр['вердикти'] if str(в.get('рука')) == '1']
        if not в1:
            continue
        в = в1[0]
        виклики = в['етапи']['виклики']
        кроки = []
        for в_ in виклики:
            т = str(в_.get('відповідь_сира') or '').strip()
            x = (за_текстом.get(т) or [None])[0] if т else None
            сек = x['с'] if x else None
            крок = в_.get('крок') + ('·' + str(в_.get('крок_спроба')) if в_.get('крок_спроба') else '')
            кроки.append((крок, сек))
            if сек is not None:
                сек_кроків[в_.get('крок')].append(сек)
        клік, картка = ходи.get(прохід, (None, None))
        до_картки = round((картка - клік).total_seconds()) if клік and картка else None
        # лінія часу від кліку: початок і кінець кожного виклику руки 1 (обмін моста), мовний шар картки руки 1
        лінія = []
        for в_ in виклики:
            т = str(в_.get('відповідь_сира') or '').strip()
            x = (за_текстом.get(т) or [None])[0] if т else None
            if x and клік:
                п0 = (D.datetime.fromisoformat(x['час'].replace('Z', '+00:00')) - клік).total_seconds()
                лінія.append((в_.get('крок'), п0, п0 + x['с']))
        шар = [(D.datetime.fromisoformat(м['коли'].replace('Z', '+00:00')) - клік).total_seconds() + int(м.get('мс') or 0) / 1000
               for м in (в.get('мова_шару') or []) if м.get('коли') and клік]
        лінія_ч = None
        if лінія and до_картки is not None:
            ск = [л for л in лінія if л[0] == 'assembly']
            оп = [л for л in лінія if л[0] == 'description']
            if ск and оп:
                лінія_ч = dict(до_складання=round(ск[0][1]), складання=round(ск[0][2] - ск[0][1]),
                               ремонт_вибір=round(оп[0][1] - ск[0][2]), опис=round(оп[-1][2] - оп[0][1]),
                               шар=round((max(шар) if шар else оп[-1][2]) - оп[-1][2]),
                               до_показу=round(до_картки - (max(шар) if шар else оп[-1][2])))
        # образи складання, ремонту й вибору
        скл = next((к for к in виклики if к.get('крок') == 'assembly'), None)
        рем = next((к for к in виклики if к.get('крок') == 'repair'), None)
        виб = next((к for к in виклики if к.get('крок') == 'choice'), None)
        повн_до = [к for к in виклики if к.get('крок') == 'completeness']
        обрано = ((виб or {}).get('вибір') or {})
        назва = обрано.get('обрано') or обрано.get('замінено') or ''
        карт = склад({'ід': (виб or {}).get('повнота', {}).get('ід') if виб else []})
        образи_скл = {о.get('номер'): о for о in ((скл or {}).get('образи_кроку') or [])}
        образи_рем = {о.get('номер'): о for о in ((рем or {}).get('образи_кроку') or [])}
        о_скл = образи_скл.get(назва)
        ремонт_змінив = None if not (о_скл and карт) else (склад(о_скл) != карт)
        чистий_у_скл = None if not о_скл else not (о_скл.get('блокери') or гейти(о_скл))
        перший = min(образи_рем.values(), key=ключ) if образи_рем else None
        перший_скл = min(образи_скл.values(), key=ключ) if образи_скл else None
        чистих_скл = sum(1 for о in образи_скл.values() if not (о.get('блокери') or гейти(о)))
        чистих_рем = sum(1 for о in образи_рем.values() if not (о.get('блокери') or гейти(о)))
        вибір_код = None if not (перший and назва) else (перший.get('номер') == назва)
        ярус = None if not (перший and назва in образи_рем) else (ключ(образи_рем[назва])[:4] == ключ(перший)[:4])
        рядки.append(dict(с=с, прохід=прохід, до_картки=до_картки, лінія=лінія_ч, кроки=кроки, викликів=len(виклики),
                          обрано=назва, ремонт_змінив=ремонт_змінив, чистий_у_складанні=чистий_у_скл,
                          перший_коду=(перший or {}).get('номер'), вибір_як_код=вибір_код, у_першому_ярусі=ярус,
                          перший_коду_складання=(перший_скл or {}).get('номер'),
                          чистих_складання=чистих_скл, з=len(образи_скл), чистих_ремонту=чистих_рем,
                          з_рем=len(образи_рем), повнота_до_вибору=len(повн_до)))

for р in рядки:
    print('%s п%d · лінія, с: %s' % (р['с'], р['прохід'], р['лінія']))
for р in рядки:
    print('%s п%d · до картки %s с · викликів %d · %s · обрано %s · ремонт змінив обраний: %s · обраний чистий уже в '
          'складанні: %s · перший коду (ремонт) %s → вибір як код: %s (той самий ярус: %s) · чистих у складанні %d/%d, '
          'після ремонту %d/%d' % (
              р['с'], р['прохід'], р['до_картки'], р['викликів'],
              ' + '.join('%s %s' % (к, ('%.1f' % s) if s is not None else '?') for к, s in р['кроки']),
              р['обрано'], р['ремонт_змінив'], р['чистий_у_складанні'], р['перший_коду'], р['вибір_як_код'],
              р['у_першому_ярусі'], р['чистих_складання'], р['з'], р['чистих_ремонту'], р['з_рем']))
n = len(рядки)
print('\nпроходів', n)
for к, сс in sorted(сек_кроків.items()):
    сс = sorted(сс)
    print('крок %-12s викликів %2d · с: мін %.1f · медіана %.1f · макс %.1f · сума %.0f' % (
        к, len(сс), сс[0], сс[len(сс) // 2], сс[-1], sum(сс)))
def част(поле, знач=True):
    з = [р for р in рядки if р[поле] is not None]
    return '%d з %d' % (sum(1 for р in з if р[поле] == знач), len(з))
print('ремонт НЕ змінив обраний образ:', част('ремонт_змінив', False))
print('обраний образ без блокерів і гейтів уже в складанні:', част('чистий_у_складанні'))
print('вибір = перший образ коду (ключ_образу, з id):', част('вибір_як_код'))
print('вибір у першому ярусі коду (блокери/гейти рівні з першим):', част('у_першому_ярусі'))
for к in ('до_складання', 'складання', 'ремонт_вибір', 'опис', 'шар', 'до_показу'):
    зн = sorted(р['лінія'][к] for р in рядки if р['лінія'])
    print('лінія %-13s с: мін %d · медіана %d · макс %d' % (к, зн[0], зн[len(зн) // 2], зн[-1]))
до = sorted(р['до_картки'] for р in рядки if р['до_картки'] is not None)
сума_руки = [sum(s for _, s in р['кроки'] if s is not None) for р in рядки]
print('«Зібрати»→перша картка, с: %s; сума викликів руки 1, с: мін %.0f · макс %.0f' % (до, min(сума_руки), max(сума_руки)))
