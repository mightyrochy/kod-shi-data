"""Окремо рахує винятки моста, помилки відповіді моделі та зміни збережених викликів."""
import gzip
import json
from pathlib import Path


def main():
    """Зберігає порівняння обох записів без зарахування відхилень як успішних образів."""
    т = Path(__file__).resolve().parent
    підсумок = []
    for сцена in ("палітра_її", "плитка_робота"):
        дані = {м: [json.loads(р) for р in gzip.decompress((т / (сцена + "-" + м + ".jsonl.gz")).read_bytes()).decode("utf8").splitlines()][1:]
                for м in ("до", "після")}
        запис = dict(сцена=сцена)
        for м, рядки in дані.items():
            відхилення = [dict(н=р["н"], ім=р["ім"], відповідь_помилки=р["результат"]["відповідь_помилки"])
                for р in рядки if isinstance(р.get("результат"), dict) and р["результат"].get("відповідь_помилки")]
            запис[м] = dict(викликів=len(рядки), винятків=sum("помилка" in р for р in рядки), відхилення=відхилення)
        запис["змінено_викликів"] = sum(д != п for д, п in zip(дані["до"], дані["після"]))
        підсумок.append(запис)
        print(сцена, {м: dict(викликів=запис[м]["викликів"], винятків=запис[м]["винятків"],
                              відповідь_помилки=len(запис[м]["відхилення"])) for м in дані})
    (т / "повтор-порівняння.json").write_text(json.dumps(підсумок, ensure_ascii=False, indent=2), encoding="utf8")


if __name__ == "__main__":
    main()
