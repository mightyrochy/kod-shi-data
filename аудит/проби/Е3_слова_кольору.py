"""Слова кольору речі: вето пулу й траурний регістр на всьому каталозі — ДО і ПІСЛЯ одного визначення.

Запуск (модель і платні API не викликаються):
    python3 аудит/проби/Е3_слова_кольору.py <корінь дерева> <каталог.pickle.gz>
Каталог — `feed._прочитати_каталог(feed.каталог_на_диску(), ліміт_фото=0)` збережений pickle-ом,
щоб обидва дерева читали ті самі записи. Друкує лічбу й відбиток рішень; порівнюють два запуски.
"""
import gzip, hashlib, json, os, pickle, sys, warnings
from pathlib import Path


def головна():
    """Рішення вето пулу за кожним словом словника кольору й траурні ознаки кольору — для кожної речі."""
    дерево, каталог_шлях = Path(sys.argv[1]).resolve(), sys.argv[2]
    os.chdir(дерево / "джерела")
    sys.path.insert(0, str(Path.cwd()))
    warnings.simplefilter("ignore")
    import пакет_моделі as М, траурний_регістр as Т, словник_кольору as СК
    with gzip.open(каталог_шлях, "rb") as ф:
        каталог = pickle.load(ф)
    # Вето — слова лексикону (як їх кладе `паспорт_нагоди`) і слова, що є лише в `колір_ім`
    # чи `колір_назва_фото` (саме там три поля могли б розійтися).
    слова = sorted(set(СК.НАЗВА_ПРОДУКТУ.values()))
    рішення, вето_знято, траур = [], 0, {"прикраса_кольором": 0, "регістрова": 0, "біля_обличчя": 0}
    for r in каталог:
        знято = [w for w in слова if (М.жорстке_відсічення(r, вето={"кольори": [w]}) or "").startswith("person_veto")]
        вето_знято += len(знято)
        т = (Т._прикраса_кольором(r), Т.регістрова_річ(r), Т.біля_обличчя(r))
        траур["прикраса_кольором"] += т[0]
        траур["регістрова"] += т[1]
        траур["біля_обличчя"] += т[2]
        рішення.append((r.get("id"), знято, т))
    відбиток = hashlib.sha256(json.dumps(рішення, ensure_ascii=False, default=str).encode()).hexdigest()
    print(json.dumps(dict(речей=len(каталог), слів_вето=len(слова), пар_звірено=len(каталог) * len(слова),
                          знято_вето=вето_знято, **траур, відбиток=відбиток), ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(головна())
