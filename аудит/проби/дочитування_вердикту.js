/** Читає слова з першого запиту перекладу вердикту, без виправлень формату. */
function словаВердикту(тіло) {
  const текст = тіло?.messages?.at(-1)?.content?.find(б => б.type === 'text')?.text;
  if (!текст?.includes('"her_comment"')) return null;
  try {
    const {her_comment, tapped, format_error} = JSON.parse(текст);
    return tapped && !format_error && typeof her_comment === 'string' ? her_comment : null;
  } catch (збій) {
    if (!(збій instanceof SyntaxError)) throw збій;
    return null;
  }
}

/** Синхронізує фонове дочитування коментаря при записі й відтворенні сцени вердиктів. */
function дочитуванняВердикту(показ, обмін, записуємо) {
  let слова, записів = 0, відповідей = 0, спостерігаємо = false;

  /** Спостерігає за початком і завершенням дочитувань тієї самої картки. */
  async function почати(позиція, коментар) {
    const кількість = обмін ? обмін.записи.filter(з => з.відповідь.status === 200 && словаВердикту(з.запит) === коментар).length : 0;
    if (!кількість && !записуємо) return;
    спостерігаємо = await показ.evaluate(([поз, текст]) => {
      if (typeof дочитатиКоментарП !== 'function') return false;
      const прочитати = дочитатиКоментарП, обіцянки = window.__дочитуванняСтенда = [];
      дочитатиКоментарП = (п, покоління) => {
        const свій = п === поз && відповідь(п).коментар === текст;
        const робота = прочитати(п, покоління);
        if (свій) обіцянки.push(робота);
        return робота;
      };
      return true;
    }, [позиція, коментар]);
    if (спостерігаємо) { слова = коментар; записів = кількість; }
  }

  /** Віддає відповідь після старту наступного дочитування, якщо запис застав зміну до відповіді. */
  async function передВідповіддю(тіло, статус) {
    if (!записів || статус !== 200 || словаВердикту(тіло) !== слова || ++відповідей >= записів) return;
    await показ.waitForFunction(число => window.__дочитуванняСтенда.length >= число,
      відповідей + 1, {timeout: 120000});
  }

  /** Чекає завершення розпочатої роботи перед підсумком сцени. */
  async function завершити() {
    if (спостерігаємо) await показ.evaluate(() => Promise.all(window.__дочитуванняСтенда));
  }

  return {почати, передВідповіддю, завершити};
}

module.exports = {дочитуванняВердикту};
