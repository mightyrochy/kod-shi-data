# Збирає `джерела/проби/еталон_розбору.json` (наряд РЗ-Е): вибірка й сирі джерела — з `еталон_вибірка.py`, правда з фото,
# опора тексту й суд над рядком features — з `аудит/перевірки/рз-е/правда.py` (записав суддя очима). Кожне джерело
# зводиться до кодів розбору і судиться ТІЄЮ САМОЮ функцією `суд`, якою проба міряє будь-який новий розбір.
# Запуск: python3 аудит/проби/еталон_збірка.py <тека з вибірка.json>
import sys, os, ast, json
ТУТ = os.path.dirname(os.path.abspath(__file__)); Д = os.path.join(ТУТ, '..', '..', 'джерела')
sys.path.insert(0, Д); os.chdir(Д)
import внутрішня_мова as ВМ, verify as V, каталог_розбір as КР
ПРОБА = os.path.join(Д, 'проби', 'еталон_частки.py')
_дерево = ast.parse(open(ПРОБА, encoding='utf-8').read())   # лише функції проби: один суд на еталон і на новий розбір
exec(compile(ast.Module([в for в in _дерево.body if isinstance(в, ast.FunctionDef)], []), ПРОБА, 'exec'))
exec(open(os.path.join(ТУТ, '..', 'перевірки', 'рз-е', 'правда.py'), encoding='utf-8').read())
ВИБІРКА = json.load(open(os.path.join(os.path.abspath(sys.argv[1]), 'вибірка.json'), encoding='utf-8'))
ПОЛЯ = ['slot', 'item_type', 'length', 'sleeve', 'neckline', 'cut', 'fabric', 'pattern', 'color', 'shine', 'metal', 'set_parts']
НАЗАД = {т: {str(у): к for к, у in м.items()} for т, м in ВМ.ТАБЛИЦЯ.items()}
ДОВЖИНА = {'литка': 'midi', 'стегно': 'mid_thigh', 'максі': 'maxi', 'міні': 'mini', 'талія': 'waist', 'коліно': 'knee'}
def колір(слово):
    return слово and (НАЗАД['color_name'].get(слово) or НАЗАД['color_name'].get(V.назва_кольору(слово) or ''))
def тканина(слово):
    return слово and (НАЗАД['fabric'].get(слово) or НАЗАД['material'].get(слово))
def візерунок(слово):
    return слово and ('solid' if слово in ('solid', 'однотонний') else НАЗАД['pattern'].get(слово))
def блиск(б):
    return None if б is None else ('yes' if б >= 1 else 'no')
def продукт(з, взуття):
    """(б) — що продукт знає сьогодні: запис `фід_каталог` (словники + фото v2) і `що_каже_код` для рукава й вирізу.
    Друге значення — чи поле з тексту (словник), чи з фото (`*_джерело` == «фото»): хибний код зі слова без опори — вигадка."""
    б, сл = з['б'], з['б_словники']
    коди = dict(slot=НАЗАД['slot'].get(б['слот'] or ''), item_type=НАЗАД['item_type'].get(б['тип'] or ''),
                length=сл.get('shaft') if взуття else ДОВЖИНА.get(б['довжина_рівень']), sleeve=сл.get('sleeve'),
                neckline=сл.get('neckline'), cut=б['крій'], fabric=тканина(б['волокно']), pattern=візерунок(б['візерунок']),
                color=колір(б['колір_назва']), shine=блиск(б['блиск']), metal=КР._МЕТАЛ_В_КОД.get(б['метал']), set_parts='нема поля')
    з_фото = dict(length=б['довжина_джерело'], cut=б['крій_джерело'], fabric=б['волокно_джерело'], pattern=б['візерунок_джерело'],
                  color=б['колір_назва_джерело'], shine=б['блиск_джерело'])
    return коди, {п: з_фото.get(п) != 'фото' for п in ПОЛЯ}
def збагачення(в, взуття):
    """(в) — сирий запис qwen3-vl з `каталог_збагачення.json.gz`: лише поля, які він має; решта — «нема поля»."""
    if not в or в.get('помилка'):
        return {п: 'нема поля' for п in ПОЛЯ}
    коди = {п: 'нема поля' for п in ПОЛЯ}
    коди.update(length='нема поля' if взуття else ДОВЖИНА.get(в.get('довжина')), cut=в.get('крій'), fabric=тканина(в.get('матеріал')),
                pattern=візерунок(в.get('візерунок')), color=колір((в.get('колір_основний') or {}).get('слово')), shine=блиск(в.get('блиск')))
    return коди
речі = []
for з in ВИБІРКА:
    н = з['н']; пр = {п: П[н][п] for п in ПОЛЯ}; оп = ОПОРА[н]; взуття = 'shoes' in пр['slot']
    а = {п: (sorted(ч[0] for ч in Т[н][п]) if п == 'set_parts' and п in Т[н] else Т[н].get(п)) for п in ПОЛЯ}
    б, текстова_б = продукт(з, взуття); в = збагачення(з['в'], взуття); г = з_розбору(з['г'], взуття)
    суди = lambda коди, текстова: {п: 'нема поля' if коди[п] == 'нема поля' else суд(пр[п], оп.get(п, []), коди[п], текстова(п))
                                   for п in ПОЛЯ}
    речі.append(dict(н=н, id=з['id'], група=з['група'], кадри=з['кадри'], правда=пр, деталь=П[н]['деталь'], ключі=П[н]['ключі'],
                     примітка=П[н]['прим'], опора=оп, джерела=dict(а=а, б=б, в=в, г=г),
                     вердикти=dict(а=суди(а, lambda п: False), б=суди(б, lambda п: текстова_б[п]), в=суди(в, lambda п: False),
                                   г=суди(г, lambda п: True)),
                     features=dict(рядок=з['г'].get('features'), деталь=F[н][0], вигадка=F[н][1])))
ОПИС = ('Еталон правди про речі каталогу (наряд РЗ-Е, рядок 404 дошки). Правда кожного поля — з фото картки очима судді '
        '(`фід_фото.кадри_речі`, перші 4 кадри): перелік прийнятних кодів розбору; «НВ» — з фото не видно; «НЗ» — поле до речі '
        'не застосовне; [] — коду для того, що на фото, у переліку нема (чесна відповідь лише unknown). «опора» — коди, які '
        'підтримує текст крамниці. Джерела: а — текст крамниці; б — продукт сьогодні (фід_каталог: словники + фото v2); '
        'в — фото-збагачення qwen3-vl; г — розбір MamayLM (гілка claude/rz1-rozbir-zlyttia). Вердикти — функцією `суд` '
        'проби `еталон_частки.py`.')
json.dump(dict(опис=ОПИС, поля=ПОЛЯ, речі=речі), open(os.path.join(Д, 'проби', 'еталон_розбору.json'), 'w', encoding='utf-8'),
          ensure_ascii=False, indent=1)
print('еталон: %d речей → джерела/проби/еталон_розбору.json' % len(речі))
