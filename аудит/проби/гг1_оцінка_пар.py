import importlib.util, gzip, json, glob, os, sys, collections as K
ТУТ = os.path.dirname(os.path.abspath(__file__))
сп = importlib.util.spec_from_file_location("Р", os.path.join(ТУТ, "гг1_повтор_ремонту.py")); Р = importlib.util.module_from_spec(сп); сп.loader.exec_module(Р)
