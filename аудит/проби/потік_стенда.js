/* Стан показу читаємо без очікування тиші моста: вона настає вже після складання. */
function подіяЗбору(умова){
  const стан = зрізЗбиранняП();
  const тепер = {почато: стан.почато || 0, зайнято: стан.зайнято, готово: !!стан.готово,
    статус: стан.статус, прогін: П?.прогін ?? null,
    картки: [...document.querySelectorAll('#картки .картка, #mirror-look-sides .pair-outfit')]
      .some(к => к.getClientRects().length > 0)};
  if (!умова) return тепер;
  if (тепер.почато && тепер.почато !== умова.до.почато){
    if (умова.етап === 'старт') return тепер;
    const картки = тепер.картки && тепер.прогін !== умова.до.прогін;
    if (картки && (умова.етап === 'перша' || (тепер.готово && !тепер.зайнято)))
      return {...тепер, час: Date.now()};
    if (тепер.готово && !тепер.зайнято && !стан.успіх)
      return {...тепер, відмова: тепер.статус.код || 'збір завершився без карток'};
  }
  if (тепер.статус.подій !== умова.до.статус.подій && тепер.статус.код && !тепер.зайнято)
    return {...тепер, відмова: тепер.статус.код};
  return null;
}

const показ = стор => стор.показПідЧасМоста || стор;
const станЗбору = стор => показ(стор).evaluate(подіяЗбору);
const новийЗбір = (до, після) => Boolean(після.почато && до.почато !== після.почато);

async function чекатиЗбір(стор, до, етап, timeout){
  const ручка = await показ(стор).waitForFunction(подіяЗбору, {до, етап}, {timeout});
  try { return await ручка.jsonValue(); }
  finally { await ручка.dispose(); }
}

async function початиЗбір(стор, до, дотик, timeout){
  const тепер = await станЗбору(стор);
  if (новийЗбір(до, тепер)) return {...тепер, розмова: true};
  await дотик();
  return чекатиЗбір(стор, до, 'старт', timeout);
}

async function згорнутиРозмовуПари(стор){
  const закрити = стор.locator('#mirror-conversation [data-ux="collapse"]');
  if (await закрити.isVisible()) await закрити.click();
}

module.exports = {станЗбору, новийЗбір, чекатиЗбір, початиЗбір, згорнутиРозмовуПари};
