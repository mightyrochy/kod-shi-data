# -*- coding: utf-8 -*-
"""Е3-одна-величина ч29 (п.7, клас довжини → точка на тілі): край верхнього шару зі слова і халява взуття ДО → ПІСЛЯ.

Запуск із кореня репозиторію:
    python3 аудит/проби/Е3_ч29_верхнє_халява.py                       # ПІСЛЯ: код цієї гілки
    git worktree add /tmp/до <SHA_ДО>
    python3 аудит/проби/Е3_ч29_верхнє_халява.py --код /tmp/до/джерела  # ДО: той самий скрипт на старому коді

Каталог — як у `Е3_ч26_клас_довжини.py` (стенд, `bridge.виклик("запити")`); модель і платні API не викликаються. Тіла —
155/165/175 см. Друкує: клас довжини верхнього шару зі слова фіду і його край `верхнє_довжина.край_см` (висота, джерело);
халяву взуття за типом (`халява_рівень`, `халява_см` на тілі); `РІВЕНЬ_У_ВИСОТУ` (вигляд шкали для читача на один рівень)."""
import sys, pathlib, json, collections, os, io, contextlib

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
код = pathlib.Path(sys.argv[sys.argv.index("--код") + 1]).resolve() if "--код" in sys.argv else КОРІНЬ / "джерела"
os.chdir(код); sys.path.insert(0, str(код))
import feed as Ф, bridge as B, fit as ПС, верхнє_довжина as ВД, аксесуари_взуття as АВ

вх = json.load(open(код / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску(str(КОРІНЬ / "джерела" / "каталог_повний.xml")); вх["гілка"] = 0
with contextlib.redirect_stdout(io.StringIO()):
    json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
print(f"код: {код}  · речей каталогу {len(кат)}")
ТІЛА = {зр: ПС.тіло(зр, dict(плечі=98, груди=92, талія=74, стегна=100)) for зр in (155, 165, 175)}
print("РІВЕНЬ_У_ВИСОТУ:", dict(ВД.РІВЕНЬ_У_ВИСОТУ))

верх = [c for c in кат if c.get("слот") == "верхній_шар" and c.get("довжина_рівень")]
клас_слово = collections.Counter((c["довжина_рівень"], c.get("довжина_джерело")) for c in верх)
print("верхній шар зі словом довжини: (клас, джерело) → речей")
for к, n in sorted(клас_слово.items(), key=lambda x: (-x[1], str(x[0]))):
    print("   %6d  %s" % (n, к))
print("край верхнього шару `край_см` (висота см, джерело): клас → на 155 / 165 / 175")
for клас in sorted({c["довжина_рівень"] for c in верх}):
    р = dict(довжина_рівень=клас)
    print("   %-10s %s" % (клас, " / ".join("%s %s" % ВД.край_см(р, t) for t in ТІЛА.values())))

халява = collections.Counter()
for c in кат:
    if c.get("слот") == "взуття":
        for зр, t in ТІЛА.items():
            y, звідки, пох = АВ.халява_з_похибкою(c, t)
            халява[(зр, c.get("халява_джерело") is not None, c.get("халява_рівень"), y, "похибка відома" if пох is not None else "похибка невідома")] += 1
print("халява взуття: (зріст, тип несе халяву, рівень, висота см, похибка) → речей")
for к, n in sorted(халява.items(), key=lambda x: (str(x[0][2]), x[0][0])):
    print("   %6d  %s" % (n, к))
