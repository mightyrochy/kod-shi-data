"""Відтворює приймання першої відповіді без моделі із запису першої спроби."""
import json
from pathlib import Path
import sys

ТЕКА = Path(__file__).resolve().parent
sys.path.insert(0, str(ТЕКА.parents[2] / "джерела"))
import мовний_шар as М


def головна():
    """Друкує фактичний паспорт та облік порад після збереженої відповіді."""
    запис = next((ТЕКА / "відповіді").glob("seed3_01_*.txt")).read_text(encoding="utf-8")
    промпт = json.loads(запис.split("──\n", 1)[1].split("\n\n── ВІДПОВІДЬ", 1)[0])
    відповідь = запис.split("── ВІДПОВІДЬ", 1)[1].split("──\n", 1)[1]
    хід = М.прийняти_розмову(відповідь)
    р = М.паспорт_з_шару(хід["внутрішня"], {}, слова_ходу=промпт["her_new_message"], частини=хід["частини"])
    паспорт = р["паспорт"]
    звіт = dict(не_взято=хід["не_взято"], намір=паспорт["намір"], місце=паспорт["місце"],
                джерело_полів=паспорт["джерело_полів"], факт_місця=паспорт["картка_запиту"]["місце"],
                теми_поради=р["теми_поради"], поради_дані=паспорт["поради_дані"])
    # Повтор мовної моделі має об'єкт заяви замість {key: текст}; приймач не вигадує переклад.
    запис = next((ТЕКА / "відповіді").glob("seed3_30_*.txt")).read_text(encoding="utf-8")
    відповідь = запис.split("── ВІДПОВІДЬ", 1)[1].split("──\n", 1)[1]
    ключ = "s_caefb4b9f9ab82eca8285490"
    розмітка = [{"ключ": ключ, "вид": "card_unchecked", "повідомлення": "питання.0",
                 "заяви": [{"code": "item_insole_length_unknown", "key": ключ}]}]
    звіт["повтор_30"] = М.прийняти_повідомлення(розмітка, відповідь)
    промпт = М.промпт_повідомлень(розмітка)
    звіт["схема_відповіді_повідомлень"] = json.loads(промпт.split("ФОРМА ВІДПОВІДІ:\n")[1].split("\nПОВІДОМЛЕННЯ:")[0]) if "ФОРМА ВІДПОВІДІ:" in промпт else None
    вивід = json.dumps(звіт, ensure_ascii=False, indent=2) + "\n"
    if len(sys.argv) > 1:
        Path(sys.argv[1]).write_text(вивід, encoding="utf-8")
    print(вивід)


if __name__ == "__main__":
    головна()
