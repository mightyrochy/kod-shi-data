# -*- coding: utf-8 -*-
"""Рядок 129: «Сумка обрана, у проблемах написано, що сумка не обрана.»
ДО — K-ACC-12 над КОЖНОЮ сумкою: «місце для «X» не обране», над річчю, яка в образі
стоїть. ПІСЛЯ — рядок питає про СПОСІБ НОСІННЯ її словами, а де спосіб називає сама
картка, місце виводиться й питання зникає. `python3 аудит/проби/misce_sumky_129.py`."""
import sys, json, pathlib, collections
_К = pathlib.Path(__file__).resolve().parent.parent.parent / "джерела"
sys.path.insert(0, str(_К)); __import__("os").chdir(_К)
import bridge as B, accessory as АК

вх = json.load(open("стенд_вх.json", encoding="utf-8")); вх["гілка"] = 0
json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
сумки = [c for c in кат if c.get("слот") == "сумка"]
шарфи = [c for c in кат if c.get("слот") == "шарф"]
л = collections.Counter()
for b in сумки:  # скільки сумок несуть кожне поле й скільком місце виводиться
    л["місця в рядку"] += bool(b.get("місця")); л["ремінь_см"] += b.get("ремінь_см") is not None
    л["формат"] += bool(b.get("формат")); л["МІСЦЕ ВИВЕДЕНО"] += bool(b.get("місце"))
    if b.get("місце"): л["   ← " + ("коротка ручка" if "ручка" in b["місце_джерело"][:6]
                                     else b["місце_джерело"])] += 1
print("сумок у пакеті %d · шарфів %d" % (len(сумки), len(шарфи)))
for k, v in list(л.most_common()) + [("вибір лишається жінці", len(сумки) - л["МІСЦЕ ВИВЕДЕНО"]),
                                     ("шарфів із виведеним місцем", sum(1 for c in шарфи if c.get("місце")))]:
    print("  %-28s %d" % (k, v))
assert л["місця в рядку"] == len(сумки), "«місця» не доїхали до рядка каталогу"
assert л["МІСЦЕ ВИВЕДЕНО"], "жодній сумці місце не виводиться — крок вибору знову мертвий"

def рядок(р):
    з = АК.місце_не_обране([р])
    return з[0]["суть"] if з else "— питання знято: %s" % р["місце_джерело"]

відкрита = next(b for b in сумки if not b.get("місце"))
виведена = next(b for b in сумки if b.get("місце"))
for ім, р in (("сумка · картка мовчить", відкрита), ("сумка · картка каже", виведена),
              ("шарф", шарфи[0])):
    print("%s\n  ДО:    місце для «%s» не обране\n  ПІСЛЯ: %s"
          % (ім, р.get("назва") or "", рядок(р)))
assert not АК.місце_не_обране([виведена]), "місце виведено, а питання лишилось"
assert "не обране" not in рядок(відкрита), "старе формулювання лишилось у виході"
