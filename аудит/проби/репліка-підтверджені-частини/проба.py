"""Вимір приймача репліки й доставки: дві архівні відповіді та синтетичні контролі."""

import json
import subprocess
import sys
from itertools import islice
from pathlib import Path

ТЕКА = Path(__file__).resolve().parent
КОРІНЬ = ТЕКА.parents[2]
БАЗА = "002d9c34e062ba7b53ecf60e2bb51e1564782b09"
sys.path.insert(0, str(КОРІНЬ / "джерела"))

import bridge
import мовний_шар as мова

ПІДТВЕРДЖЕННЯ = "Я записала, що ти хочеш «оцю свою синю сукню»."
ВИРОК = "Сукня тобі пасує за умови, що інша річ образу врівноважить її крій."
ЗАПИТАННЯ = "Де буде ця подія?"


def архів():
    """Відкрити лише два JSONL-записи перекладача репліки."""
    шлях = ТЕКА.parent / "Прохід-через-міст-2026-11-21/ч3_фото_примірка/обміни.jsonl"
    with шлях.open(encoding="utf-8") as файл:
        перша, друга = map(json.loads, islice(файл, 5, 7))
    запити = [json.loads(р["запит"])["messages"][-1]["content"][-1]["text"] for р in (перша, друга)]
    репліка, повтор = [json.loads(з.split("РЕПЛІКА:\n", 1)[1]) for з in запити]
    assert репліка == повтор
    відповіді = [json.loads(р["відповідь"])["content"][0]["text"] for р in (перша, друга)]
    return репліка, відповіді


def код_бази(шлях):
    """Прочитати точну базу з Git без зміни робочого дерева."""
    return subprocess.check_output(("git", "show", f"{БАЗА}:{шлях}"), cwd=КОРІНЬ, text=True)


def доставка(назва, репліка, відповіді, запрошення, *, код=None):
    """Передати VM результати справжнього моста для кожного запиту та відповідей."""
    вхід = {"репліка": репліка, "паспорт": {}, "запрошення": запрошення}
    кроки = []
    причина = None
    for і, відповідь in enumerate(відповіді):
        запит = dict(вхід, помилка_формату=причина) if і else вхід
        вихід = dict(вхід, відповідь_моделі=відповідь)
        if і:
            вихід["перша_відповідь"] = відповіді[0]
        промпт = json.loads(bridge.виклик("мова", json.dumps(запит, ensure_ascii=False)))
        результат = json.loads(bridge.виклик("мова", json.dumps(вихід, ensure_ascii=False)))
        assert "промпт" in промпт and "текст" in результат
        зміст = json.loads(промпт["промпт"].split("РЕПЛІКА:\n", 1)[1])
        assert зміст.get("item_verdicts") == репліка.get("item_verdicts")
        if і:
            assert "Розбіжність попередньої відповіді:" in промпт["промпт"]
        кроки.append({"запит": запит, "вихід": вихід, "промпт": промпт, "результат": результат})
        причина = результат.get("причина")
    дані = {"репліка": репліка, "запрошення": запрошення, "кроки": кроки, "код": код}
    запуск = subprocess.run(
        ("node", str(ТЕКА / "доставка.cjs")), input=json.dumps(дані, ensure_ascii=False),
        text=True, capture_output=True, check=True,
    )
    результат = json.loads(запуск.stdout)
    print(f"{назва}: {результат['спроб']} спроб(и); {результат['запис'].get('причина') or 'повна'}")
    return результат


def відповідь(*речення):
    """Оформити синтетичні речення у відповідь перекладача."""
    return json.dumps({"text": речення}, ensure_ascii=False)


def головна(до):
    """Виміряти втрату на базі або прийняття кандидата й негативні випадки."""
    код_показу = None
    if до:
        exec(compile(код_бази("джерела/мовний_шар.py"), мова.__file__, "exec"), vars(мова))
        bridge.мова = мова.мова
        код_показу = код_бази("джерела/показ/мовний_шар.js")
    репліка, відп = архів()
    запрошення = репліка["advice"]
    перша = мова.прийняти_репліку(відп[0], репліка, запрошення)
    повтор = мова.прийняти_репліку(відп[1], репліка, запрошення, **({} if до else {"після_повтору": True}))
    for і, (сира, прийнята) in enumerate(zip(відп, (перша, повтор)), 5):
        суд = мова.суд_речень_репліки(json.loads(сира)["text"], репліка)
        print(f"Індекс {і}: суд {sum(д for _, д, _ in суд)}/{len(суд)}, "
              f"показ {len(прийнята['текст'])} симв., причина {прийнята['причина']}, "
              f"відмов {len(прийнята['відкинуто'])}")
    assert перша["причина"] == "no_card_confirmation: wants" and not перша["текст"]
    assert повтор["причина"] == "not_about_recorded"
    вхід = {к: в for к, в in репліка.items() if к in ("recorded", "item_verdicts")}
    показ = доставка("Архів ч3", вхід, відп, запрошення, код=код_показу)
    if до:
        assert повтор["текст"] == "" and показ["запис"]["запасний_текст"]
        assert показ["текст"] == f"оцю свою синю сукню\n{запрошення}"
        return

    assert показ["текст"] == повтор["текст"] and показ["спроб"] == 2
    assert показ["запис"]["причина"] == повтор["причина"]
    assert показ["запис"]["повтор"]["причина"] == перша["причина"]
    assert len(показ["запис"]["повтор"]["відкинуто"]) == 13 and "запасний_текст" not in показ["запис"]
    assert len(повтор["відкинуто"]) == 25 and all(
        р["зняте"] not in повтор["текст"] and р["чому"] == "not_about_recorded" for р in повтор["відкинуто"]
    )
    assert повтор["текст"].startswith(f"{ПІДТВЕРДЖЕННЯ} {ВИРОК}")
    assert повтор["текст"].count(запрошення) == 1
    for річ in ("жакет на фото:", "верх на фото (внутрішній шар):", "шарф на фото:", "спідницю на фото:"):
        assert f"Про {річ}" in повтор["текст"]

    добре = json.loads(відп[1])["text"][0]
    число = dict(добре, says="Сукня коштує 314159 гривень.")
    умова = dict(добре, says=f"{ПІДТВЕРДЖЕННЯ} Також потрібна окрема оплата.")
    без_опори = dict(добре, about=["невідома_умова"], recorded=[], her_words=[], says="Це вже погодили.")
    чуже = dict(добре, her_words=["синю су"], says="Я записала побажання.")
    мішана = відповідь(умова, число, без_опори, чуже)
    вих = доставка("Сторожі речень", вхід, [мішана, мішана], запрошення)
    assert вих["текст"] == f"{ПІДТВЕРДЖЕННЯ} {запрошення}"
    assert [р["чому"] for р in вих["запис"]["відкинуто"]] == [
        "not_about_recorded", "unrecorded_number", "not_about_recorded", "no_card_confirmation",
    ]
    assert "запасний_текст" not in вих["запис"]

    у_лапках = "Ти сказала: «оцю свою синю сукню.»"
    форма = відповідь(dict(добре, says=у_лапках + " Також потрібна окрема оплата."),
                      dict(добре, about=[["wants"]]), {"says": "Це вже погодили."}, None)
    вих = доставка("Межа речення за лапками та биті поля", вхід, [форма, форма], "")
    assert вих["текст"] == у_лапках and вих["спроб"] == 2
    assert [р["чому"] for р in вих["запис"]["відкинуто"]] == [
        "not_about_recorded", "invalid_sentence_fields", "invalid_sentence_fields", "invalid_sentence_fields",
    ]

    латинка = dict(добре, about=["item_verdicts"], recorded=[], her_words=[], says="You should buy another dress.")
    латинка_і_число = відповідь(добре, латинка, число)
    вих = доставка("Чуже письмо після повтору", вхід, [мішана, латинка_і_число], запрошення)
    assert вих["текст"] == f"{ПІДТВЕРДЖЕННЯ} {запрошення}" and вих["спроб"] == 2
    assert [р["чому"] for р in вих["запис"]["відкинуто"]] == ["unrecorded_number", "foreign_language"]
    гола_латинка = відповідь(латинка, число)
    чуже_запрошення = "Tell me what accessories to choose?"
    вих = доставка("Відхилене запрошення не вертається запасним шляхом", вхід,
                   [мішана, гола_латинка], чуже_запрошення)
    assert вих["текст"] == "оцю свою синю сукню" and вих["запис"]["запасний_текст"]
    assert not вих["запис"]["запрошення_питанням"]

    з_питанням = dict(вхід, required=["event_place"])
    питання = {"about": ["required"], "recorded": [], "her_words": [], "says": ЗАПИТАННЯ}
    перепит = dict(питання, about=["occasion"], says="Куди ти йдеш?")
    хибна = відповідь(перепит, питання, добре)
    вих = доставка("Невиконане required", з_питанням, [хибна, хибна], запрошення)
    assert вих["текст"] == ПІДТВЕРДЖЕННЯ and вих["спроб"] == 2
    assert вих["запис"]["причина"].startswith("required_question_missing")
    assert {р["чому"] for р in вих["запис"]["відкинуто"]} == {
        "question_not_required", "question_not_last", "required_question_missing",
    }

    часткова = відповідь(добре, число, питання)
    вих = доставка("Питання дійшло, репліка часткова", з_питанням, [хибна, часткова], запрошення)
    assert вих["текст"] == f"{ПІДТВЕРДЖЕННЯ} {ЗАПИТАННЯ}" and вих["спроб"] == 2
    assert вих["запис"]["причина"] == "unrecorded_number"
    assert "запрошення_питанням" not in вих["запис"]

    чуже_питання = відповідь(добре, число, dict(питання, says="Where is the event?"))
    вих = доставка("Останнє питання зняв мовний сторож", з_питанням, [хибна, чуже_питання], запрошення)
    assert вих["текст"] == ПІДТВЕРДЖЕННЯ and вих["спроб"] == 2
    assert [р["чому"] for р in вих["запис"]["відкинуто"]] == [
        "unrecorded_number", "foreign_language", "required_question_missing",
    ]

    повна = доставка("Повна відповідь з required", з_питанням, [відповідь(добре, питання)], "")
    assert повна["текст"] == f"{ПІДТВЕРДЖЕННЯ} {ЗАПИТАННЯ}" and повна["спроб"] == 1
    assert "причина" not in повна["запис"] and "відкинуто" not in повна["запис"]
    повна = доставка("Повна відповідь без required", вхід, [відповідь(добре)], запрошення)
    assert повна["текст"] == f"{ПІДТВЕРДЖЕННЯ} {запрошення}" and повна["спроб"] == 1

    непридатна = відповідь(число, чуже)
    вих = доставка("Без придатних речень", вхід, [мішана, непридатна], запрошення)
    assert вих["текст"] == f"оцю свою синю сукню\n{запрошення}"
    assert вих["запис"]["запасний_текст"] and вих["запис"]["причина"] == "unrecorded_number"
    гола = {"item_verdicts": вхід["item_verdicts"]}
    вих = доставка("Без придатних речень і запасного тексту", гола, [непридатна, непридатна], "")
    assert вих["текст"] == "" and вих["запис"]["запасний"]

    каталог = {"item_verdicts": [
        {"item_id": "first", "catalogue_position": 1, "verdict": {"kind": "her_item_verdict", "statements": []}},
        {"item_id": "second", "catalogue_position": 2, "verdict": {"kind": "her_item_verdict", "statements": []}},
        {"verdict": {"kind": "catalogue_search", "statements": []}},
    ]}
    прогноз = {"about": ["item_verdicts"], "recorded": [], "her_words": []}
    перший = dict(прогноз, says="У першого светра колір лишився невідомим.")
    другий = dict(прогноз, says="У другого светра довжина лишилася невідомою.")
    втручання = dict(прогноз, says="Другий светр коштує 314159 гривень.")
    вих = доставка("Вердикти каталогу у власному порядку", каталог,
                   [відповідь(перший, втручання, другий)] * 2, "")
    assert вих["текст"] == перший["says"] + " " + другий["says"]
    print("Архівний і 12 синтетичних контролів пройшли.")


if __name__ == "__main__":
    головна("--до" in sys.argv)
