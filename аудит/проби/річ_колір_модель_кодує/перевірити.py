def перевірити_сусідство():
    """Звіряє геометричні пари з незалежним обходом комірок повного розбиття."""
    осі, сітка = блоки.МЕЖІ.розбити_простір(блоки.клітинки(), {i: i for i in range(1, 268)})
    очікувані = {i: set() for i in range(1, 268)}
    for адреса, код in сітка.items():
        for вісь in range(3):
            сусід = list(адреса)
            сусід[вісь] += 1
            if вісь == 0:
                сусід[вісь] %= len(осі[вісь]) - 1
            інший = сітка.get(tuple(сусід))
            if інший is not None and інший != код:
                очікувані[код].add(інший)
                очікувані[інший].add(код)
    assert блоки.сусіди() == очікувані
    return sum(map(len, очікувані.values())) // 2


def перевірити_обернення():
    """Повертає свотчі у Lab і міряє числовий залишок двох явних методів."""
    colour = блоки.бібліотека()
    пряме = блоки.ПЕРЕНОС.зробити_перетворення(colour)
    свотчі = set()
    for р in прогін.прочитати_tsv(прогін.ТЕКА / "звіт.tsv"):
        свотчі.update(р["свотчі_власника"].split(" / "))
    залишки, нижні = [], []
    for hex in sorted(свотчі):
        H, V, C = блоки.свотч_у_munsell(hex)
        if V >= 1:
            lab, _ = пряме(H, V, C)
        else:
            вузли = dict(блоки.нижній_овоід(V))
            h = H % 100
            початок = math.floor(h / 2.5) * 2.5
            частка = (h - початок) / 2.5
            a, b = вузли[початок], вузли[(початок + 2.5) % 100]
            білий = colour.notation.munsell.CCS_ILLUMINANT_MUNSELL
            xy = [білий[i] + C / 2 * ((1 - частка) * a[i] + частка * b[i] - білий[i])
                  for i in range(2)]
            Y = float(colour.notation.munsell.luminance_ASTMD1535(V)) / 100
            xyz = colour.xyY_to_XYZ([*xy, Y])
            lab = блоки.простір.адаптувати_освітлювач(colour.XYZ_to_Lab(
                xyz, illuminant=colour.XYZ_to_xy(блоки.простір.БІЛІ["C"])))
            нижні.append(hex)
        залишок = math.dist(lab, блоки.простір.hx(hex))
        assert залишок < 1e-5, (hex, залишок)
        залишки.append(залишок)
    return {"свотчів": len(свотчі), "макс_залишок_Lab": max(залишки),
            "нижня_таблична_інтерполяція": нижні}


def перевірити_вхід():
    """Будує всі запити без мережі й звіряє кількість кадрів із вибраною галереєю."""
    вхід = прогін.прочитати_json(прогін.ТЕКА / "наступний_вхід.json")
    джерело = прогін.прочитати_json(прогін.КОРІНЬ / "ohliad-koloru/sets/sproba2.json")["речі"]
    assert len(вхід["речі"]) == len(джерело) == 40
    кадрів, віддалених = 0, 0
    дозволені = {к["url"] for р in вхід["речі"] for к in р["кадри"] if "url" in к}
    зразок = next(прогін.КОРІНЬ / к["файл"] for р in вхід["речі"] for к in р["кадри"] if "файл" in к)

    def локальні_байти(url, **параметри):
        """Перевіряє структуру віддаленого кадру фікстурою; мережі тут немає."""
        assert url in дозволені, "API чи інша мережа заборонена у звірці"
        return io.BytesIO(зразок.read_bytes())

    with patch("urllib.request.urlopen", side_effect=локальні_байти):
        for річ, первинна in zip(вхід["речі"], джерело):
            assert set(річ) == {"номер", "тип", "кадри"}
            assert річ["номер"] == первинна["номер"]
            assert len(річ["кадри"]) == len(первинна["галерея"])
            очікувані = [p if p.startswith("http") else "ohliad-koloru/foto/" + p
                        for p in первинна["галерея"]]
            assert [к.get("файл", к.get("url")) for к in річ["кадри"]] == очікувані
            запит = прогін.запит_моделі(вхід, річ, "перевірка-без-моделі")
            assert len(запит["messages"][1]["content"]) == 1 + len(очікувані)
            assert запит["max_tokens"] == прогін.ПАРАМЕТРИ["max_tokens"] == 2000
            кадрів += len(очікувані)
            віддалених += sum("url" in к for к in річ["кадри"])
    assert "92 -" not in вхід["system_prompt"] and "молочний/айворі" not in вхід["system_prompt"]
    return {"усіх": кадрів, "віддалених_лише_структура": віддалених}


def головна():
    """Перевіряє артефакти й записує докази разом із хешами всіх входів."""
    словник = прогін.прочитати_tsv(прогін.ТЕКА / "словник_iscc_267.tsv")
    assert len(словник) == 267
    for р in словник:
        lab = tuple(float(р[x]) for x in ("L", "a", "b"))
        assert all(math.isfinite(x) for x in lab) and lab != (50., 0., 0.)
        assert len(р["hex_центроїд"]) == 7
        assert not any(c.isascii() and c.isalpha() for c in р["назва_uk"])
    assert блоки.зіставити([{263}, {267}], [267, 263])
    assert not блоки.зіставити([{263}, {267}], [263])
    assert not блоки.зіставити([{263}, {267}], [263, 263])
    assert not блоки.спільна_грань(((1, 4), (0, 2), (0, 1)), ((4, 6), (2, 3), (0, 1)))
    assert блоки.коди_точки((1, 8.5, .5)) == блоки.коди_точки((101, 8.5, .5))
    артефакт = {"версії": {м: importlib.metadata.version(м) for м in
                           ("colour-science", "numpy", "scipy")},
                "блоків_словника": len(словник), "пар_сусідніх_блоків": перевірити_сусідство(),
                "обернення": перевірити_обернення(), "кадрів_без_API": перевірити_вхід()}
    шляхи = [блоки.МЕЖІ.КЛІТИНКИ, блоки.МЕЖІ.ТАБЛИЦЯ,
             прогін.ОГЛЯД / "лічба_sproba2_власник.tsv", прогін.ОГЛЯД / "ключ_sproba2.json",
             прогін.ТЕКА / "словник_iscc_267.tsv", прогін.ТЕКА / "наступний_вхід.json"]
    шляхи += [прогін.ТЕКА / f"відповіді_моделі_{м}.json" for м in прогін.МОДЕЛІ]
    артефакт["входи_sha256_lf"] = {ш.relative_to(прогін.КОРІНЬ).as_posix():
        hashlib.sha256(ш.read_text(encoding="utf-8").encode("utf-8")).hexdigest() for ш in шляхи}
    прогін.записати_json(прогін.ТЕКА / "перевірка_спроби4.json", артефакт)
    print(f"Перевірено: {len(словник)} блоків; {артефакт['пар_сусідніх_блоків']} пар сусідів; "
          f"{артефакт['обернення']['свотчів']} свотчів; {артефакт['кадрів_без_API']['усіх']} кадрів без API")


if __name__ == "__main__":
    головна()
