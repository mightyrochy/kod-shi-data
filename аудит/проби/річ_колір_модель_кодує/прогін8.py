"""Спроба 8: мала модель називає відтінок і принт своїми словами — те саме прохання, що мала модель хмарної сесії
(`вартість/вимір.py`, ПРОХАННЯ): галерея речі, без словника, переліків, ознак і коду.

    python прогін8.py --вхід 40|13 [--тека-фото ТЕКА] --модель М --вихід ФАЙЛ [--продовжити]
"""
import argparse
import json
import re
import urllib.request
from pathlib import Path

import прогін as П
import прогін_13 as П13

АДРЕСА = "http://127.0.0.1:1234/v1/chat/completions"
ПРОХАННЯ = ('На всіх доданих кадрах галереї опиши колір цільової речі: {тип}. '
            'Назви відтінок і принт своїми словами українською, як для людини; '
            'у двоколірної речі назви обидва кольори. Відділяй тканину від тла, '
            'шкіри, інших речей, тіней, блиску та освітлення. Без словника, '
            'переліків, кодів і hex. Відповідь — лише JSON з полями '
            '"назва" та "принт" (null, коли принту немає). '
            'Працюй лише з доданими зображеннями, без інструментів, файлів та мережі.')
ПАРАМЕТРИ = {"temperature": 0.0, "max_tokens": 2000}


def запит(вхід, річ, модель):
    """Той самий збір кадрів, що в усіх прогонах (640×640, JPEG 85); текст — лише прохання."""
    з = П.запит_моделі(вхід, річ, модель)
    зміст = з["messages"][1]["content"]
    зміст[0] = {"type": "text", "text": ПРОХАННЯ.format(тип=річ["тип"].lower())}
    return {"model": модель, "messages": [{"role": "user", "content": зміст}], **ПАРАМЕТРИ}


def головна():
    а = argparse.ArgumentParser(description=__doc__)
    а.add_argument("--вхід", choices=("40", "13"), required=True)
    а.add_argument("--тека-фото", type=Path)
    а.add_argument("--модель", required=True)
    а.add_argument("--вихід", type=Path, required=True)
    а.add_argument("--продовжити", action="store_true")
    а = а.parse_args()
    вхід = П.прочитати_json(П.ТЕКА / "наступний_вхід.json")
    if а.вхід == "13":
        вхід = П13.вхід_13(а.тека_фото)
    if а.вихід.exists() and not а.продовжити:
        raise ValueError("Для нової спроби потрібен новий файл виходу")
    результати = П.прочитати_json(а.вихід) if а.вихід.exists() else {}
    for річ in вхід["речі"]:
        н = str(річ["номер"])
        if н in результати:
            continue
        з = запит(вхід, річ, а.модель)
        р = urllib.request.Request(АДРЕСА, data=json.dumps(з).encode("utf-8"), headers={"Content-Type": "application/json"})
        with urllib.request.urlopen(р, timeout=300) as в:
            сире = json.loads(в.read())
        if сире["choices"][0]["finish_reason"] == "length":
            raise ValueError(f"Річ {н}: відповідь усічено")
        текст = сире["choices"][0]["message"]["content"].strip()
        try:
            дані = json.loads(re.sub(r"^```(?:json)?\s*|\s*```$", "", текст))
        except ValueError:
            дані = None
        результати[н] = {"сира_відповідь": текст, "назва": (дані or {}).get("назва"), "принт": (дані or {}).get("принт"),
                         "json_ок": дані is not None, "кадрів": len(річ["кадри"])}
        П.записати_json(а.вихід, результати)
        print(f"Готово: {len(результати)}/{len(вхід['речі'])}", flush=True)
    П.записати_json(а.вихід.with_suffix(".метадані.json"), {
        "модель": а.модель, "параметри": ПАРАМЕТРИ, "розмір_кадру": вхід["розмір_кадру"],
        "прохання": ПРОХАННЯ, "готово": len(результати)})


if __name__ == "__main__":
    головна()
