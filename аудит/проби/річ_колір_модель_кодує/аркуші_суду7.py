"""Аркуші суду очима, спроба 7: відповіді моделі упереміш із контролем словника, без позначки, що є що.

    python аркуші_суду7.py <вихідна_тека> --13 <тека_фото_приймання> [--ключ ФАЙЛ]
Рядок — річ (вся галерея), свотчі коду з назвою й часткою, поле «принт». Для кожної з 40 речей є два рядки: відповідь
моделі й контроль — центральний зразок блоку, у якому лежить свотч власника (підібраний чи визнаний; у двоколірної —
обидва блоки). Контроль має частки й «принт» тієї ж відповіді моделі (на вигляд не відрізняється; принт суддя
оцінює лише за рядками моделі). Мітки Р01…Р80 випадкові; ключ «мітка → річ, модель чи контроль» — окремий файл,
судді його не відкривати. 13 речей приймання — лише модель, мітки П1…П13.
"""
import argparse
import random
from pathlib import Path

from PIL import Image, ImageDraw

import аркуші_суду as А
