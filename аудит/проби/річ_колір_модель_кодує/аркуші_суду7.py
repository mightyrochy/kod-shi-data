from лічба_прогін7 import блок_свотча

ВИСОТА = 290
МОДЕЛЬ = "qwen3-vl-8b-instruct"


def ближчий_блок(hex, словник, номери):
    """Серед блоків свотча (на грані їх кілька) — той, чий центр ближчий за L*a*b*."""
    from colour import XYZ_to_Lab, sRGB_to_XYZ
    import numpy as np
    lab = XYZ_to_Lab(sRGB_to_XYZ(np.array([int(hex[i:i + 2], 16) / 255 for i in (1, 3, 5)])))
    return min(номери, key=lambda н: sum((a - float(словник[str(н)][к])) ** 2 for a, к in zip(lab, "Lab")))


def малювати(полотно, y, мітка, зразки, принт, кадри):
    """Один рядок: мітка, принт, свотчі, мініатюри кадрів."""
    д = ImageDraw.Draw(полотно)
    д.text((8, y + 4), мітка, fill="black", font=А.ШРИФТ)
    д.text((8, y + 24), f"принт: {принт or '—'}"[:44], fill="black", font=А.ШРИФТ)
    for i, (код, назва, частка, hex) in enumerate(зразки):
        д.rectangle((8, y + 52 + i * 78, 120, y + 108 + i * 78), fill=hex, outline="black")
        д.text((126, y + 56 + i * 78), f"{код} {назва}"[:26], fill="black", font=А.ШРИФТ)
        д.text((126, y + 78 + i * 78), f"частка {частка:g}", fill="black", font=А.ШРИФТ)
    x = 400
    for к in кадри:
        з = А.кадр(к)
        з.thumbnail((А.ШИРИНА, 200))
        if x + з.width > А.ШИРИНА:
            break
        полотно.paste(з, (x, y + 4))
        x += з.width + 6


def рядки_40(словник, вхід, відповіді):
    """Рядки моделі й контролю для 40 речей: (річ, вид, зразки, принт)."""
    ключ = П.прочитати_json(П.ОГЛЯД / "ключ_sproba2.json")["речі"]
    таблиця = {р["номер"]: р for р in П.прочитати_tsv(П.ОГЛЯД / "лічба_sproba2_власник.tsv")}
    результат = []
    for річ in вхід["речі"]:
        н = str(річ["номер"])
        відповідь = відповіді[н]["відповідь"]
        зразки_моделі = А.зразки_коду(словник, відповідь)
        результат.append((річ, "модель", зразки_моделі, відповідь.get("принт")))
        свотчі = П.еталонні_свотчі(таблиця[н], ключ[н])
        коди = [ближчий_блок(h, словник, блок_свотча(h)) for h in свотчі]
        частки = [к[2] for к in зразки_моделі] if len(коди) == len(зразки_моделі) else \
            ([1.0] if len(коди) == 1 else [0.7, 0.3])
        контроль = [(к, словник[str(к)]["назва_uk"], ч, словник[str(к)]["hex_центроїд"]) for к, ч in zip(коди, частки)]
        результат.append((річ, "контроль", контроль, відповідь.get("принт")))
    return результат


def головна():
    а = argparse.ArgumentParser(description=__doc__)
    а.add_argument("тека", type=Path)
    а.add_argument("--13", dest="фото13", type=Path, required=True)
    а.add_argument("--ключ", type=Path, default=П.ТЕКА / "ключ_контролю_не_для_судді.json")
    а = а.parse_args()
    а.тека.mkdir(parents=True, exist_ok=True)
    словник = {р["код"]: р for р in П.прочитати_tsv(П.ТЕКА / "словник_iscc_267.tsv")}
    вхід = П.прочитати_json(П.ТЕКА / "наступний_вхід.json")
    відповіді = П.прочитати_json(П.ТЕКА / f"відповіді_прогін7_{МОДЕЛЬ}.json")
    рядки = рядки_40(словник, вхід, відповіді)
    random.Random(20261116).shuffle(рядки)
    ключ = {}
    групи = [(рядки[п:п + 5], "") for п in range(0, len(рядки), 5)]
    from прогін_13 import вхід_13
    вх13 = вхід_13(а.фото13)
    for річ in вх13["речі"]:
        річ["кадри"] = [{"файл": к["файл"]} for к in річ["кадри"]]
    в13 = П.прочитати_json(П.ТЕКА / f"відповіді_прогін7_13_{МОДЕЛЬ}.json")
    рядки13 = [(річ, "модель", А.зразки_коду(словник, в13[str(річ["номер"])]["відповідь"]),
                в13[str(річ["номер"])]["відповідь"].get("принт")) for річ in вх13["речі"]]
    групи += [(рядки13[п:п + 5], "П") for п in range(0, len(рядки13), 5)]
    лічильник = 0
    for номер, (група, префікс) in enumerate(групи, 1):
        полотно = Image.new("RGB", (А.ШИРИНА, ВИСОТА * len(група) + 8), "white")
        for i, (річ, вид, зразки, принт) in enumerate(група):
            if префікс:
                мітка = f"П{річ['номер']}  {річ['тип']}"
            else:
                лічильник += 1
                мітка = f"Р{лічильник:02d}  {річ['тип']}"
                ключ[мітка.split()[0]] = {"річ": річ["номер"], "вид": вид}
            малювати(полотно, i * ВИСОТА, мітка, зразки, принт, річ["кадри"])
        ім = f"аркуш_{'П' if префікс else ''}{номер:02d}.jpg"
        полотно.save(а.тека / ім, quality=85)
        print(ім)
    П.записати_json(а.ключ, ключ)


if __name__ == "__main__":
    головна()
