def вибір_контролю():
    """Бере саме функцію вибору з аркушів, без запуску малювання та шрифтів."""
    шлях = ТЕКА / "аркуші_суду7.py"
    дерево = ast.parse(шлях.read_text(encoding="utf-8"))
    функція = next(вузол for вузол in дерево.body
                   if isinstance(вузол, ast.FunctionDef) and вузол.name == "ближчий_блок")
    область = {}
    exec(compile(ast.Module(body=[функція], type_ignores=[]), str(шлях), "exec"), область)
    return область[функція.name]


def xyz_під_C(hex):
    """Повторює зворотний Bradford із блоки.py без зміни білих чи масштабу Y."""
    простір = блоки.простір
    xyz = простір.to_xyz(простір.hx(hex))
    від = простір._множ(простір._BRADFORD, простір.БІЛІ["D65"])
    до = простір._множ(простір._BRADFORD, простір.БІЛІ["C"])
    lms = простір._множ(простір._BRADFORD, xyz)
    return простір._множ(простір._BRADFORD_ОБЕРНЕНА,
                         tuple(lms[i] * до[i] / від[i] for i in range(3)))


def верхні_вузли(colour):
    """Читає повні хроматичні вузли V=9,10, з яких складено табличний овоїд."""
    munsell = colour.notation.munsell
    результат = {}
    for (тон, V, C), xyY in munsell.MUNSELL_COLOURS_ALL:
        if V not in (9, 10):
            continue
        h, _, _, сектор = munsell.munsell_colour_to_munsell_specification(f"{тон} {V}/{C}")
        H = float(munsell.hue_to_ASTM_hue([h, сектор])) % 100
        результат[V, H, C] = tuple(map(float, xyY[:2]))
    білий = tuple(map(float, munsell.CCS_ILLUMINANT_MUNSELL))
    for V in (9, 10):
        for H in (i * 2.5 for i in range(40)):
            результат[V, H, 0.] = білий
    return результат


def таблична_верхня_точка(hex, V, colour, вузли):
    """Обертає трикутники повної таблиці V=9…10, зберігаючи хроматичні вузли V=10.

    До C=2 це той самий метод, що вже є у блоки.низький_свотч.
    Далі — ті самі дві трикутні половини кожної табличної H/C-комірки.
    Це контроль узгодженості з даними, не ремонт чинного перетворення.
    """
    import numpy as np
    munsell = colour.notation.munsell
    xyY = colour.XYZ_to_xyY(xyz_під_C(hex))
    вага = ((float(xyY[2]) * 100 - float(munsell.luminance_ASTMD1535(9))) /
            (float(munsell.luminance_ASTMD1535(10)) - float(munsell.luminance_ASTMD1535(9))))
    if not 0 < вага < 1:
        raise ValueError("Свотч поза верхнім інтервалом таблиці")
    точки = { (H, C): (1 - вага) * np.array(a) + вага * np.array(вузли[10, H, C])
              for (рівень, H, C), a in вузли.items()
              if рівень == 9 and (10, H, C) in вузли }
    рівні = sorted({C for H, C in точки})
    for низ, верх in zip(рівні, рівні[1:]):
        for i in range(40):
            H0, H1 = i * 2.5, (i + 1) * 2.5
            кути = ((H0, низ), (H1, низ), (H1, верх), (H0, верх))
            if not all((H % 100, C) in точки for H, C in кути):
                continue
            # Перша невироджена половина C=0 — біла точка й два вузли C=2.
            for індекси in ((0, 1, 2), (0, 2, 3)):
                hc = np.array([кути[j] for j in індекси])
                xy = np.array([точки[H % 100, C] for H, C in hc])
                матриця = np.column_stack((xy[1] - xy[0], xy[2] - xy[0]))
                if abs(float(np.linalg.det(матриця))) < 1e-18:
                    continue
                u, v = np.linalg.solve(матриця, xyY[:2] - xy[0])
                if min(u, v, 1 - u - v) < 0:
                    continue
                барицентр = np.array([1 - u - v, u, v])
                H, C = барицентр @ hc
                # На нейтральній осі H не визначений; на C>0 інтерполюємо
                # тон за частками саме хроматичних вершин, як низький_свотч.
                if низ == 0:
                    H = float(sum(w * H * c for w, (H, c) in zip(барицентр, hc)) / C)
                залишок = float(np.linalg.norm(барицентр @ xy - xyY[:2]))
                if залишок > 1e-12:
                    raise ValueError("Не підтверджено табличне обернення")
                return ((H - 1) % 100 + 1, V, float(C)), залишок
    raise ValueError(f"{hex}: не знайдено трикутника повної верхньої таблиці")


def межі_свідка(точка, код):
    """Дає справжню H/V/C-клітинку обраного блоку або порожній рядок."""
    H, V, C = точка
    for номер, межі in блоки.клітинки():
        if номер == код and any(блоки.містить(межі, (тон, V, C))
                                for тон in ((H, 101.) if H == 1 else (H,))):
            return "; ".join(f"{вісь}=[{низ:g},{верх:g}]" for вісь, (низ, верх) in zip("HVC", межі))
    return "немає"


def числа(значення):
    """Форматує одну або кілька величин у порядку свотчів."""
    return " / ".join(f"{x:.6f}" if isinstance(x, float) else str(x) for x in значення)


def рядок_таблиці(значення):
    """Екранує клітинки Markdown і не породжує додаткових рядків."""
    return "| " + " | ".join(str(x).replace("|", "\\|").replace("\n", " ") for x in значення) + " |"


def посилання_на_код(файл, фрагмент):
    """Знаходить чинний номер рядка доказу, відмовляє при неоднозначності."""
    рядки = файл.read_text(encoding="utf-8").splitlines()
    номери = [i for i, рядок in enumerate(рядки, 1) if фрагмент in рядок]
    if len(номери) != 1:
        raise ValueError(f"Неоднозначне джерело: {файл.name}, {фрагмент}")
    return f"{файл.relative_to(КОРІНЬ).as_posix()}:{номери[0]}"


