"""Числа спроби 8 з вердиктів судді (`суд_прогін8.tsv`) і ключа. Запускати лише після коміту вердиктів.

    python лічба_прогін8.py
Правильних за джерелом (модель / власник / сильна) окремо для 40 речей `sproba2` і 13 речей приймання; контроль судді —
рядки «власник»: менше 38 з 40 — суддя не мірка, і число малої моделі — «гіпотеза», не висновок.
"""
import collections
import json

import прогін as П


def головна():
    ключ = П.прочитати_json(П.ТЕКА / "ключ_прогін8_не_для_судді.json")["рядки"]
    вердикти = {р["мітка"]: р for р in П.прочитати_tsv(П.ТЕКА / "суд_прогін8.tsv")}
    чисельник, знаменник = collections.Counter(), collections.Counter()
    for мітка, к in ключ.items():
        в = вердикти[мітка]["вердикт"].strip().lower()
        п = (к["набір"], к["джерело"])
        знаменник[п] += 1
        чисельник[п] += в == "правильно"
    for п in sorted(знаменник):
        print(f"{п[0]:12} {п[1]:8} правильно {чисельник[п]} з {знаменник[п]}")
    хибні = [(к["набір"], к["номер"], к["джерело"], к["текст"], вердикти[м]["причина"]) for м, к in ключ.items()
             if вердикти[м]["вердикт"].strip().lower() != "правильно"]
    print(json.dumps(хибні, ensure_ascii=False, indent=1))


if __name__ == "__main__":
    головна()
