"""Лічба спроби 7: допоміжні числа (блок, перші дев'ять рядків словника, склад ознак) і таблиця причин; моделей не
запускає. Мірило продукту — суд очима за `аркуші_прогін7/` (`аркуші_суду7.py`), цей скрипт його не замінює.

    python лічба_прогін7.py [МОДЕЛЬ]
"""
import json
import sys

import блоки
import прогін as П
from лічба_прогін6 import коди_відповіді

МОДЕЛЬ = sys.argv[1] if len(sys.argv) > 1 else "qwen3-vl-8b-instruct"


def блок_свотча(hex):
    """Блоки, що містять свотч (на грані — кілька)."""
    return блоки.коди_точки(блоки.свотч_у_munsell(hex))


def головна():
    відповіді = П.прочитати_json(П.ТЕКА / f"відповіді_прогін7_{МОДЕЛЬ}.json")
    рядки = [р for р in П.прочитати_tsv(П.ОГЛЯД / "лічба_sproba2_власник.tsv") if int(р["номер"]) <= 40]
    ключ = П.прочитати_json(П.ОГЛЯД / "ключ_sproba2.json")["речі"]
    звіт = []
    for рядок in рядки:
        н = рядок["номер"]
        відповідь = відповіді[н]["відповідь"]
        свотчі = П.еталонні_свотчі(рядок, ключ[н])
        еталони = [блок_свотча(h) for h in свотчі]
        коди = коди_відповіді(відповідь, len(свотчі) > 1)
        точно = блоки.зіставити(еталони, коди)
        сусід = not точно and блоки.зіставити(еталони, коди, із_сусідами=True)
        к2 = відповіді[н]["крок2"]
        звіт.append({"номер": н, "тони": " ".join(к["тон"] for к in к2),
                     "ознаки": " | ".join(f"{к['світлість']}/{к['друга_ознака']}" for к in к2),
                     "коди_моделі": " ".join(map(str, коди)), "основний_у_перших_9": int(відповідь["основний"]["код"] <= 9),
                     "назва_моделі": відповідь["назва"], "принт_моделі": відповідь.get("принт") or "",
                     "свотчі_власника": " / ".join(свотчі),
                     "блоки_свотчів": " / ".join(" ".join(map(str, sorted(к))) for к in еталони),
                     "блок_точно": "ТАК" if точно else "НІ", "лише_сусідній_блок": int(сусід),
                     "ознаки_не_за_переліком_точно": int(not all(к["точно"] for к in к2))})
    П.записати_tsv(П.ТЕКА / f"звіт_прогін7_{МОДЕЛЬ}.tsv", звіт)
    підсумок = {"блок_точно": sum(р["блок_точно"] == "ТАК" for р in звіт),
                "лише_сусідній_блок": sum(р["лише_сусідній_блок"] for р in звіт),
                "основний_у_перших_9": sum(р["основний_у_перших_9"] for р in звіт),
                "речей_з_найближчим_блоком_замість_точного": sum(р["ознаки_не_за_переліком_точно"] for р in звіт),
                "речей": len(звіт)}
    П.записати_json(П.ТЕКА / f"підсумок_прогін7_{МОДЕЛЬ}.json", підсумок)
    print(json.dumps(підсумок, ensure_ascii=False))


if __name__ == "__main__":
    головна()
