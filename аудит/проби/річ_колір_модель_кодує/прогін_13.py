"""Ті самі коди для 13 речей, не зарахованих прийманням 15.11: той самий промпт, параметри й розмір кадру.

    python прогін_13.py <тека_фото> --вихід НОВИЙ_ФАЙЛ [--прогін МОДЕЛЬ]
Фото — з гілки `claude/Річ-колір-вимір` (`річ_колір_перезбір_0411/фото`); моделі йдуть лише кадри й тип речі,
без назви крамниці, адреси й вердикту приймання. Без --прогін лише готує й перелічує вхід.
"""
import argparse
import hashlib
import json
import urllib.request
from pathlib import Path

import прогін as П

ПРИЙМАННЯ = П.КОРІНЬ / "аудит/проби/річ_колір_приймання_1511"
ТИПИ = {1: "светр", 4: "штани", 5: "штани", 8: "куртка", 11: "сукня", 13: "штани", 17: "сукня", 23: "штани",
        24: "сукня", 31: "сукня", 32: "джемпер", 33: "сорочка", 40: "пальто"}


def вхід_13(тека_фото):
    """Усі кадри кожної з 13 речей приймання (поле `фото`), у первинному порядку."""
    базовий = П.прочитати_json(ТЕКА_ВХОДУ)
    речі = {н: [] for н in ТИПИ}
    for р in П.прочитати_tsv(ПРИЙМАННЯ / "вибірка.tsv"):
        н = int(р["номер"])
        if н in речі:
            шлях = Path(тека_фото) / Path(р["фото"]).name
            if hashlib.sha256(шлях.read_bytes()).hexdigest() != р["sha256"]:
                print(f"УВАГА: sha256 файла {шлях.name} відрізняється від вибірки (знімок у вибірці — інший кадр?)")
            речі[н].append({"файл": шлях.as_posix(), "sha256": hashlib.sha256(шлях.read_bytes()).hexdigest()})
    return {**базовий, "речі": [{"номер": н, "тип": ТИПИ[н], "кадри": к} for н, к in речі.items()]}


ТЕКА_ВХОДУ = П.ТЕКА / "наступний_вхід.json"


def головна():
    а = argparse.ArgumentParser(description=__doc__)
    а.add_argument("тека_фото")
    а.add_argument("--вихід", type=Path, required=True)
    а.add_argument("--прогін", metavar="МОДЕЛЬ")
    а = а.parse_args()
    вхід = вхід_13(а.тека_фото)
    print(f"Речей {len(вхід['речі'])}, кадрів {sum(len(р['кадри']) for р in вхід['речі'])}")
    if not а.прогін:
        return
    результати = {}
    for річ in вхід["речі"]:
        запит = urllib.request.Request("http://127.0.0.1:1234/v1/chat/completions",
            data=json.dumps(П.запит_моделі(вхід, річ, а.прогін)).encode("utf-8"),
            headers={"Content-Type": "application/json"})
        with urllib.request.urlopen(запит, timeout=300) as відповідь:
            сире = json.loads(відповідь.read())
        if сире["choices"][0]["finish_reason"] == "length":
            raise ValueError(f"Річ {річ['номер']}: відповідь усічено")
        текст = П.re.sub(r"^```(?:json)?\s*|\s*```$", "", сире["choices"][0]["message"]["content"].strip())
        результати[str(річ["номер"])] = json.loads(текст)
        П.записати_json(а.вихід, результати)
    П.записати_json(а.вихід.with_suffix(".метадані.json"), {
        "модель": а.прогін, "параметри": вхід["параметри"], "готово": len(результати),
        "словник_sha256": вхід["словник_sha256"], "типи": ТИПИ})


if __name__ == "__main__":
    головна()
