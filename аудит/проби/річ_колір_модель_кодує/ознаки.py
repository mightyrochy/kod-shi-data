"""Таблиця «ознаки → код блоку» зі словника без фото (спроба 7).

Назви блоків ISCC–NBS — «ознака + тон» («light grayish reddish brown»): модель обирає тон з короткого переліку, потім
світлість і насиченість серед тих, що словник має для цього тону; код складає ця таблиця. Нейтральні блоки (білі,
сірі, чорні, зокрема з нальотом: «pinkish gray») — тон `neutral`, а замість насиченості — нальот.

    python ознаки.py      — перевіряє, що кожен із 267 блоків дістається ознаками, і друкує перелічення
"""
import csv
from pathlib import Path

ТЕКА = Path(__file__).resolve().parent

# Префікс назви → (світлість, насиченість). Порядок: довші префікси першими.
ПРЕФІКСИ = [
    ("very deep", ("very dark", "strong")), ("very light", ("very light", "strong")),
    ("very pale", ("very light", "weak")), ("very dark", ("very dark", "moderate")),
    ("light grayish", ("light", "grayish")), ("dark grayish", ("dark", "grayish")),
    ("vivid", ("medium", "vivid")), ("brilliant", ("light", "vivid")), ("strong", ("medium", "strong")),
    ("deep", ("dark", "strong")), ("light", ("light", "moderate")), ("moderate", ("medium", "moderate")),
    ("dark", ("dark", "moderate")), ("pale", ("light", "weak")), ("grayish", ("medium", "grayish")),
    ("blackish", ("very dark", "grayish")),
]
НАЛЬОТ = {"pinkish": "pinkish", "reddish": "reddish", "brownish": "brownish", "yellowish": "yellowish",
          "olive": "olive", "greenish": "greenish", "bluish": "bluish", "purplish": "purplish"}
НЕЙТРАЛЬНІ = {"white": "white", "gray": "gray", "black": "black"}
СВІТЛОСТІ_НЕЙТР = ("white", "light gray", "gray", "dark gray", "black")
ШКАЛА_СВІТЛОСТІ = ("very light", "light", "medium", "dark", "very dark")
ШКАЛА_НАСИЧЕНОСТІ = ("vivid", "strong", "moderate", "weak", "grayish")


def розібрати(назва):
    """Назва блоку → (тон, світлість, друга ознака). Для нейтральних друга ознака — нальот (`none` — без нальоту)."""
    слова = назва.split()
    if слова[-1] in НЕЙТРАЛЬНІ:
        кінець = слова[-1]
        перед = слова[:-1]
        світлість = кінець
        if перед and перед[0] in ("light", "dark", "medium"):
            світлість = f"{перед[0]} {кінець}"
            перед = перед[1:]
        нальот = НАЛЬОТ[перед[0]] if перед else "none"
        if світлість == "medium gray":
            світлість = "gray"
        return "neutral", світлість, нальот
    for префікс, (світлість, насиченість) in ПРЕФІКСИ:
        if назва.startswith(префікс + " "):
            return назва[len(префікс) + 1:], світлість, насиченість
    return назва, "", ""  # одноблокові тони без ознаки («brownish pink», «brownish orange»)


def таблиця():
    """{(тон, світлість, друга ознака): код} зі словника; повторний ключ — помилка (блок не дістати)."""
    with (ТЕКА / "словник_iscc_267.tsv").open(encoding="utf-8") as файл:
        словник = list(csv.DictReader(файл, delimiter="\t"))
    результат, назви = {}, {}
    for рядок in словник:
        ключ = розібрати(рядок["назва_en"])
        if ключ in результат:
            raise ValueError(f"Два блоки з ознаками {ключ}: {результат[ключ]} і {рядок['код']}")
        результат[ключ] = int(рядок["код"])
        назви[int(рядок["код"])] = рядок["назва_uk"]
    return результат, назви


def тони(табл):
    """Перелік тонів у порядку словника."""
    return list(dict.fromkeys(т for т, _, _ in табл))


def варіанти(табл, тон):
    """Для тону: допустимі світлості та другі ознаки (у порядку шкали)."""
    ключі = [к for к in табл if к[0] == тон]
    світлості = {к[1] for к in ключі}
    другі = {к[2] for к in ключі}
    порядок_с = СВІТЛОСТІ_НЕЙТР if тон == "neutral" else ШКАЛА_СВІТЛОСТІ
    порядок_д = ("none",) + tuple(НАЛЬОТ) if тон == "neutral" else ШКАЛА_НАСИЧЕНОСТІ
    return ([с for с in порядок_с if с in світлості] + sorted(світлості - set(порядок_с)),
            [д for д in порядок_д if д in другі] + sorted(другі - set(порядок_д)))


def відстань(шкала, а, б):
    """Відстань на шкалі; відсутня ознака — найдальша."""
    if а not in шкала or б not in шкала:
        return len(шкала) if а != б else 0
    return abs(шкала.index(а) - шкала.index(б))


def код_блоку(табл, тон, світлість, друга):
    """Код за тоном і ознаками; (код, точно). Нема такої пари — найближчий блок тону (спершу світлість)."""
    if (тон, світлість, друга) in табл:
        return табл[(тон, світлість, друга)], True
    кандидати = [к for к in табл if к[0] == тон]
    if not кандидати:
        raise KeyError(f"Невідомий тон {тон!r}")
    шкала_с = СВІТЛОСТІ_НЕЙТР if тон == "neutral" else ШКАЛА_СВІТЛОСТІ
    шкала_д = (("none",) + tuple(НАЛЬОТ)) if тон == "neutral" else ШКАЛА_НАСИЧЕНОСТІ
    найкращий = min(кандидати, key=lambda к: (відстань(шкала_д, друга, к[2]) if тон == "neutral" else 0,
                                              відстань(шкала_с, світлість, к[1]),
                                              відстань(шкала_д, друга, к[2])))
    return табл[найкращий], False


def головна():
    табл, назви = таблиця()
    assert len(табл) == 267 and set(табл.values()) == set(range(1, 268)), "не всі 267 блоків дістаються ознаками"
    for код in range(1, 268):  # кожен блок дістається своїми ознаками точно
        ключ = next(к for к, в in табл.items() if в == код)
        assert код_блоку(табл, *ключ) == (код, True)
    тони_ = тони(табл)
    print(f"Блоків 267, тонів {len(тони_)}; кожен блок — рівно одна трійка ознак")
    for т in тони_:
        с, д = варіанти(табл, т)
        print(f"{т}: світлість {с}; {'нальот' if т == 'neutral' else 'насиченість'} {д}")


if __name__ == "__main__":
    головна()
