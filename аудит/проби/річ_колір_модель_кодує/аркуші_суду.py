"""Аркуші для суду очима: свотч точки коду моделі поруч з усією галереєю речі.

    python аркуші_суду.py <вихідна_тека> [--13 <тека_фото_приймання>]
Без назв крамниці, свотчів власника й вердиктів: суддя бачить лише галерею й колір коду (центральний зразок
блоку словника). Судить не сесія, що проганяла. Кадри 6 URL беруться з мережі, як у прогоні.
"""
import argparse
import io
import urllib.request
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

import прогін as П
import прогін_13 as П13

ШРИФТ = ImageFont.truetype("C:/Windows/Fonts/arial.ttf", 16)
ВИСОТА, ШИРИНА, РЯДКІВ = 200, 1500, 5


def зразки_коду(словник, відповідь):
    """Усі кольори відповіді: код, назва, частка, hex центрального зразка."""
    кольори = [відповідь["основний"]] + [р for р in відповідь.get("решта") or [] if р["частка"] > 0]
    return [(к["код"], словник[str(к["код"])]["назва_uk"], к["частка"], словник[str(к["код"])]["hex_центроїд"])
            for к in кольори]


def кадр(к):
    """Відкриває кадр речі: локальний файл чи URL."""
    if "файл" in к:
        return Image.open(П.КОРІНЬ / к["файл"]).convert("RGB")
    запит = urllib.request.Request(к["url"], headers={"User-Agent": "Mozilla/5.0"})
    return Image.open(io.BytesIO(urllib.request.urlopen(запит, timeout=60).read())).convert("RGB")


def рядок(полотно, y, мітка, зразки, кадри):
    """Малює одну річ: мітка, свотчі коду моделі, мініатюри всіх кадрів."""
    д = ImageDraw.Draw(полотно)
    д.text((8, y + 4), мітка, fill="black", font=ШРИФТ)
    for i, (код, назва, частка, hex) in enumerate(зразки):
        д.rectangle((8, y + 30 + i * 80, 120, y + 90 + i * 80), fill=hex, outline="black")
        д.text((126, y + 36 + i * 80), f"{код} {назва}"[:26], fill="black", font=ШРИФТ)
        д.text((126, y + 58 + i * 80), f"частка {частка:g}", fill="black", font=ШРИФТ)
    x = 400
    for к in кадри:
        з = кадр(к)
        з.thumbnail((ШИРИНА, ВИСОТА - 8))
        if x + з.width > ШИРИНА:
            break
        полотно.paste(з, (x, y + 4))
        x += з.width + 6


def аркуші(префікс, речі, словник, відповіді, тека):
    """Пише аркуші по РЯДКІВ речей."""
    for п in range(0, len(речі), РЯДКІВ):
        група = речі[п:п + РЯДКІВ]
        полотно = Image.new("RGB", (ШИРИНА, ВИСОТА * len(група) + 8), "white")
        for i, річ in enumerate(група):
            рядок(полотно, i * ВИСОТА, f"{префікс}{річ['номер']}  {річ['тип']}",
                  зразки_коду(словник, відповіді[str(річ["номер"])]), річ["кадри"])
        шлях = тека / f"аркуш_{префікс}{п // РЯДКІВ + 1:02d}.jpg"
        полотно.save(шлях, quality=85)
        print(шлях.name)


def головна():
    а = argparse.ArgumentParser(description=__doc__)
    а.add_argument("тека", type=Path)
    а.add_argument("--13", dest="фото13", type=Path)
    а = а.parse_args()
    а.тека.mkdir(parents=True, exist_ok=True)
    словник = {р["код"]: р for р in П.прочитати_tsv(П.ТЕКА / "словник_iscc_267.tsv")}
    вхід = П.прочитати_json(П.ТЕКА / "наступний_вхід.json")
    аркуші("", вхід["речі"], словник, П.прочитати_json(П.ТЕКА / "відповіді_прогін6_qwen3-vl-8b-instruct.json"), а.тека)
    if а.фото13:
        вх13 = П13.вхід_13(а.фото13)
        for річ in вх13["речі"]:
            річ["кадри"] = [{"файл": Path(к["файл"]).relative_to(П.КОРІНЬ).as_posix()
                             if Path(к["файл"]).is_relative_to(П.КОРІНЬ) else к["файл"]} for к in річ["кадри"]]
        аркуші("П", вх13["речі"], словник, П.прочитати_json(П.ТЕКА / "відповіді_13_приймання_qwen3-vl-8b-instruct.json"),
               а.тека)


if __name__ == "__main__":
    головна()
