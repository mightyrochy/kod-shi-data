"""Аркуші суду назв, спроба 8: галерея й назва словами, без свотчів, коду й словника.

    python аркуші_суду8.py <вихідна_тека> --13 <тека_фото_приймання>
Рядок — річ (усі кадри), тип і назва з принтом. Рядки впереміш, мітки Р001… випадкові, без позначки джерела:
  модель  — назва малої `qwen3-vl-8b-instruct` (`відповіді_прогін8*.json`);
  власник — назва, яку визнав власник (`річ_колір_огляд_людьми/назви.tsv`, sproba2) — контроль судді, лише 40 речей;
  сильна  — назва сильної моделі класу хмарної сесії (`вартість/назви_сильної_моделі.tsv`) — третій ряд (п.3).
Вигляд тексту вирівняно (перша літера мала, без крапки в кінці, «назва; принт» в одному рядку), щоб джерело не видавав
сам стиль. Ключ «мітка → річ, джерело» — окремий файл `ключ_прогін8_не_для_судді.json`: судді його не відкривати.
Для 13 речей приймання людських назв нема — контролю там нема: рядки моделі й сильної.
"""
import argparse
import json
import random
import textwrap
from pathlib import Path

from PIL import Image, ImageDraw

import аркуші_суду as А
import прогін as П
import прогін_13 as П13

ТЕКА_ВАРТОСТІ = П.ТЕКА / "вартість"
НАСІННЯ = 20261118
КАДРІВ_У_РЯДКУ = 7
ВИСОТА_КАДРУ = 190


def вирівняти(назва, принт):
    """«назва; принт» одним рядком, перша літера мала, без крапки в кінці."""
    текст = (назва or "").strip().rstrip(".")
    if принт and str(принт).strip().lower() not in ("null", "none", "—", "-", ""):
        текст += "; " + str(принт).strip().rstrip(".")
    return текст[:1].lower() + текст[1:]


def тексти():
    """(набір, номер) → {джерело: текст}."""
    результат = {}
    for файл, набір in (("відповіді_прогін8_qwen3-vl-8b-instruct.json", "sproba2"),
                        ("відповіді_прогін8_13_qwen3-vl-8b-instruct.json", "приймання13")):
        for н, в in П.прочитати_json(П.ТЕКА / файл).items():
            результат.setdefault((набір, int(н)), {})["модель"] = вирівняти(в["назва"], в["принт"])
    for р in П.прочитати_tsv(П.ОГЛЯД / "назви.tsv"):
        if р["набір"] == "sproba2" and ("sproba2", int(р["номер"])) in результат:
            результат[("sproba2", int(р["номер"]))]["власник"] = вирівняти(р["назва"], None)
    for р in П.прочитати_tsv(ТЕКА_ВАРТОСТІ / "назви_сильної_моделі.tsv"):
        ключ = (р["набір"], int(р["номер"]))
        if ключ in результат:
            результат[ключ]["сильна"] = вирівняти(р["назва"], р["принт"])
    return результат


КЕШ = {}


def мініатюра(к):
    ключ = json.dumps(к, sort_keys=True)
    if ключ not in КЕШ:
        з = А.кадр(к)
        з.thumbnail((400, ВИСОТА_КАДРУ))
        КЕШ[ключ] = з
    return КЕШ[ключ]


def висота(річ):
    return 8 + ВИСОТА_КАДРУ * -(-len(річ["кадри"]) // КАДРІВ_У_РЯДКУ) + 4


def малювати(полотно, y, мітка, річ, текст):
    д = ImageDraw.Draw(полотно)
    д.text((8, y + 4), f"{мітка}   {річ['тип'].lower()}", fill="black", font=А.ШРИФТ)
    for i, рядок in enumerate(textwrap.wrap(текст, 30)[:8]):
        д.text((8, y + 34 + i * 22), рядок, fill="black", font=А.ШРИФТ)
    x, лінія = 330, 0
    for i, к in enumerate(річ["кадри"]):
        if i and i % КАДРІВ_У_РЯДКУ == 0:
            x, лінія = 330, лінія + 1
        з = мініатюра(к)
        полотно.paste(з, (x, y + 4 + лінія * ВИСОТА_КАДРУ))
        x += з.width + 6
    д.line((0, y + висота(річ) - 2, А.ШИРИНА + 400, y + висота(річ) - 2), fill="gray")


def головна():
    а = argparse.ArgumentParser(description=__doc__)
    а.add_argument("тека", type=Path)
    а.add_argument("--13", dest="фото13", type=Path, required=True)
    а = а.parse_args()
    а.тека.mkdir(parents=True, exist_ok=True)
    речі = {("sproba2", р["номер"]): р for р in П.прочитати_json(П.ТЕКА / "наступний_вхід.json")["речі"]}
    for р in П13.вхід_13(а.фото13)["речі"]:
        р["кадри"] = [{"файл": к["файл"]} for к in р["кадри"]]
        речі[("приймання13", р["номер"])] = р
    джерела = тексти()
    рядки = [(ключ, дж, текст) for ключ, словник in джерела.items() for дж, текст in словник.items()]
    випадкова = random.Random(НАСІННЯ)
    випадкова.shuffle(рядки)
    ключ = {}
    аркуш, y, лист = [], 0, 1
    пакети, поточний, висота_пакета = [], [], 0
    for н, (к, дж, текст) in enumerate(рядки, 1):
        мітка = f"Р{н:03d}"
        ключ[мітка] = {"набір": к[0], "номер": к[1], "джерело": дж, "текст": текст}
        h = висота(речі[к])
        if висота_пакета + h > 1100 and поточний:
            пакети.append(поточний)
            поточний, висота_пакета = [], 0
        поточний.append((мітка, речі[к], текст))
        висота_пакета += h
    пакети.append(поточний)
    for п, пакет in enumerate(пакети, 1):
        полотно = Image.new("RGB", (А.ШИРИНА + 400, sum(висота(р) for _, р, _ in пакет) + 8), "white")
        y = 0
        for мітка, річ, текст in пакет:
            малювати(полотно, y, мітка, річ, текст)
            y += висота(річ)
        полотно.save(а.тека / f"аркуш_{п:02d}.jpg", quality=85)
        print(f"аркуш_{п:02d}: {', '.join(м for м, _, _ in пакет)}")
    (а.тека.parent / "ключ_прогін8_не_для_судді.json").write_text(
        json.dumps({"насіння": НАСІННЯ, "рядки": ключ}, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"рядків {len(рядки)}, аркушів {len(пакети)}")


if __name__ == "__main__":
    головна()
