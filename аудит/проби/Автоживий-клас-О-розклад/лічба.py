def git(*args, data=None):
    return subprocess.run(['git', *args], cwd=РЕПО, input=data,
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True).stdout


def читати_пачкою(шляхи):
    шляхи = sorted(set(шляхи))
    запити = ''.join(f'{ЗРІЗ}:{p}\n' for p in шляхи).encode('utf-8')
    потік = io.BytesIO(git('cat-file', '--batch', data=запити))
    дані = {}
    for p in шляхи:
        заголовок = потік.readline().split()
        assert len(заголовок) == 3 and заголовок[1] == b'blob', (p, заголовок)
        дані[p] = потік.read(int(заголовок[2])).decode('utf-8')
        assert потік.read(1) == b'\n'
    assert not потік.read()
    return дані


def події(текст, шлях, умова):
    return [dict(файл=шлях, рядок=i, текст=l.strip())
            for i, l in enumerate(текст.splitlines(), 1) if умова(l)]


def посилання(подія):
    p, n = подія['файл'], подія['рядок']
    relative = os.path.relpath(РЕПО / p, ТЕКА).replace('\\', '/')
    return f'[{Path(p).name}:{n}]({relative}#L{n})'


def клітинка(t):
    return str(t).replace('|', '\\|').replace('\n', ' ')


def таблиця(заголовки, рядки):
    return '\n'.join(['| ' + ' | '.join(заголовки) + ' |',
                      '| ' + ' | '.join('---' for _ in заголовки) + ' |'] +
                     ['| ' + ' | '.join(клітинка(x) for x in row) + ' |' for row in рядки])


