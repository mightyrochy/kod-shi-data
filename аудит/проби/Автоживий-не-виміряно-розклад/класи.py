#!/usr/bin/env python3
"""Клас причини кожного рядка «не виміряно»: правило — перша названа в оцінці причина; PR 3476 і 3536 — клас П (оцінка 15.11 каже, що такі питання «не виміряно» всі).
Запуск з кореня аудит/: python3 проби/Автоживий-не-виміряно-розклад/витяг.py > /tmp/r.json; python3 проби/Автоживий-не-виміряно-розклад/класи.py /tmp/r.json"""
import json,re,sys,collections
Д=json.load(open(sys.argv[1]))['рядки']
К={ 'О':('сцена обірвалась або збирання не склалось до місця питання',['не дійшла','обірван','обрив','впал','не піднявся','не дочекав','rc=','rc запуск','не заве','не склав','не склалась','не склався','порожня','не з\'явився','не дійшли','не мала образу','не склала образ','зірвалось']),
    'П':('питання про обгортку чи повтор запису, а не про продукт: живий прогін на нього не відповідає',[]),
    'Ф':('нема портрета чи фото речі: режим без +фото або без теки фото',['PORTRET','FOTO=0','+фото','нема фото','Немає фото','без фото','`PORTRET`','Фото `']),
    'Д':('нема порівняльного ДО (суд ДО, replay_опори, запис на старій збірці)',['порівняльн','replay_опори','суд ДО','не запускались','порівняння','не гірше за ДО','ДО питання не називає']),
    'С':('сцена не ставить умову питання (нема ходу, об\'єкта чи кроку, яких питання вимагає)',['нема','немає','не відбулось','не виконувався','не викликав','remove=[]','не проявився','не подавався','не задано']),
}
ручні={'Х1115 28':'Ф','Х1115 38':'Ф','Е1115 157':'Ф','Х1115 33':'С','Х1115 34':'С','Е1115 84':'С','Е1115 198':'О','Е1115 178':'Д','Е1115 187':'Д'}
def клас(r):
    if r['pr'] in('3476','3536'): return 'П'
    t=re.sub(r'\[[^\]]*\]\([^)]*\)','',r['відповідь']+' '+r['причина'])
    поз={}
    for к,(_,ks) in К.items():
        for k in ks:
            i=t.find(k)
            if i>=0: поз[к]=min(поз.get(к,9999),i)
    return min(поз,key=поз.get) if поз else '?'
ряд=[]
for r in Д: r['клас']=ручні.get(r['оцінка']+' '+str(r['рядок']),клас(r)); ряд.append(r)
if __name__=='__main__':
    c=collections.Counter(r['клас'] for r in ряд)
    for k,n in c.most_common(): print(k,n,К.get(k,('?',))[0])
    if len(sys.argv)>2:
        for r in ряд:
            if r['клас']==sys.argv[2]: print(r['оцінка'],r['рядок'],r['pr'],r['сцена'],'|',(r['відповідь']+' '+r['причина'])[:260].replace('\n',' '))
