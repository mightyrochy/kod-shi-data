"""Промпт вибору палітри (`вибір_палітри.ВИБІР` + `дані_промпта`) — ДО і ПІСЛЯ одного імені ключа випадку.

Запуск (модель і платні API не викликаються):
    python3 -I аудит/проби/Е3_ключ_випадку.py <корінь дерева>
Профіль ж2 (`аудит/проби/жінки/ж2.json`), випадок рядком і без нього; друкує JSON зібраних промптів і, для
порівняння, ключі `case` рук 3–4 (`руки_без_коду.випадок_кодами`) тієї самої нагоди. Два запуски порівнюють побайтно.
"""
import json, os, sys, warnings
from pathlib import Path


def головна():
    """Зібрані промпти палітри одного дерева → JSON у stdout."""
    корінь = Path(sys.argv[1]).resolve()
    os.chdir(корінь / "джерела")
    sys.path.insert(0, str(Path.cwd()))
    warnings.simplefilter("ignore")
    import вибір_палітри as ВП, збирач_промптів as З, руки_без_коду as Р
    ж2 = json.loads((корінь / "аудит/проби/жінки/ж2.json").read_text(encoding="utf-8"))
    вихід = []
    for випадок in ("", "побачення ввечері в ресторані", "офіс, нарада з клієнтом"):
        вхід = dict(зріст=168, обхвати={"плечі": 98, "груди": 92, "талія": 74, "стегна": 99},
                    шкіра=ж2["skin"], волосся=ж2["hair"], очі=ж2["eyes"], випадок=випадок)
        пер = ВП.перелік(вхід)
        дані = ВП.дані_промпта(пер)
        промпт = З.зібрати(ВП.ВИБІР, дані)
        руки = Р.випадок_кодами(None, випадок) if випадок else None
        вихід.append(dict(випадок=випадок, ключі_даних=sorted(дані), промпт=промпт,
                          ключі_case_рук_3_4=sorted(руки) if isinstance(руки, dict) else руки))
    print(json.dumps(вихід, ensure_ascii=False, sort_keys=True, indent=0, default=str))
    return 0


if __name__ == "__main__":
    sys.exit(головна())
