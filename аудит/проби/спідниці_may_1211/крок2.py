def пікселі(ф, р):   # той самий крій, що `пікселіРечіП` показу: поле 0.12, довга сторона 128
    im = Image.open(У + файли[ф] + '-image.jpg').convert('RGB'); W, H = im.size
    дx, дy = (р['право'] - р['ліво']) * 0.12, (р['низ'] - р['верх']) * 0.12
    л, в, п, н = max(0, р['ліво'] - дx), max(0, р['верх'] - дy), min(1000, р['право'] + дx), min(1000, р['низ'] + дy)
    x0, y0 = round(л / 1000 * W), round(в / 1000 * H)
    ш, вс = max(1, round((п - л) / 1000 * W)), max(1, round((н - в) / 1000 * H))
    ядро = dict(ліво=round((р['ліво'] - л) / (п - л) * 1000), верх=round((р['верх'] - в) / (н - в) * 1000),
                право=round((р['право'] - л) / (п - л) * 1000), низ=round((р['низ'] - в) / (н - в) * 1000))
    к = min(1, 128 / max(ш, вс)); w, h = max(1, round(ш * к)), max(1, round(вс * к))
    кр = im.crop((x0, y0, x0 + ш, y0 + вс)).resize((w, h), Image.LANCZOS)
    return dict(дані=base64.urlsafe_b64encode(кр.tobytes()).decode().rstrip('='), ширина=w, висота=h, ядро=ядро)
