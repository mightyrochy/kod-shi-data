import json
import random
import re
from pathlib import Path
from urllib.parse import urlsplit

ТЕКА = Path(__file__).resolve().parent
ПРОБИ = ТЕКА.parent
КРАМНИЦІ_ПЕРЕЛІКУ = ("brenda.ua", "cultboutique.com.ua", "gepur.com", "alot.com.ua", "www.miraton.ua", "natali-style.com.ua")
ЗОБРАЖЕННЯ = re.compile(r"\.(?:jpe?g|png|webp|avif)$", re.I)
ОСНОВА = re.compile(r"(?:\.resize\d*)?\.[a-z0-9]{3,4}$|[-_]?\d{2,5}x\d{2,5}(?:q\d+)?|^\d{2,5}x\d{2,5}(?:q\d+)?-", re.I)


def читати(шлях):
    with gzip.open(шлях, "rt", encoding="utf-8") as потік:
        return {р["ід"]: р for р in map(json.loads, потік)}


def крамниця(р):
    return urlsplit(р["адреса"]).netloc


def не_кадри(фото):
    """Класи адрес запису, що не є кадром речі: не зображення, логотип, дубль кадру під іншим іменем файла."""
    клас, основи = collections.Counter(), collections.Counter()
    for а in фото:
        шлях = urlsplit(а).path
        файл = шлях.rsplit("/", 1)[-1]
        if not ЗОБРАЖЕННЯ.search(файл):
            клас["не_зображення"] += 1
        if re.search(r"logo", файл, re.I):
            клас["логотип"] += 1
        основи[ОСНОВА.sub("", файл).lower()] += 1
    клас["дубль_кадру"] = sum(н - 1 for н in основи.values() if н > 1)
    return клас


