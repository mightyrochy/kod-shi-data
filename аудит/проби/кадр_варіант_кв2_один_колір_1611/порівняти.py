    # --- адреси, що не є кадром, у крамницях переліку
    адреси = {}
    for назва, р in (("ДО", до), ("ПІСЛЯ", після)):
        c = collections.Counter(); записів = collections.Counter(); усього = 0
        for х in р.values():
            if крамниця(х) not in КРАМНИЦІ_ПЕРЕЛІКУ or х["стан"] == "без_відповіді" or "запис" not in х:
                continue
            фото = х["запис"]["фото"]; усього += len(фото)
