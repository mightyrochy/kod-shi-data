    # --- вибірка очима 16.11: суворий розріз за адресами `запис.фото`
    вибірка = list(csv.DictReader((ПРОБИ / "кадр_варіант_кв1_очима_1511/вибірка.tsv").open(encoding="utf-8"), delimiter="\t"))
