"""Повтор кв2 на кеші HTML без мережі: той самий вимір, що кв1-писач, але причина «нема свідчення одного кольору»
знімається, коли писач має доказ платформи (`свідчення_одного_кольору`: сторінка товару крамниці з `один_колір.tsv`
без переліку кольорів). Решта — `повтор.py` кв1-писач без змін (писач → канонічний запис → чинний читач усіх кадрів)."""
import sys
from pathlib import Path

ПРОБИ = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ПРОБИ / "кадр_варіант_кв1_канал_1411"), str(ПРОБИ / "кадр_варіант_кв1_писач_1511")]
import вимір                                    # noqa: E402
import повтор as база                           # noqa: E402

_ПРИЧИНА = "нема_свідчення_одного_кольору"
_старі_причини = вимір.причини


def причини(факти, ж):
    """Причини виміру 14.11, без «нема свідчення», коли свідчення дає писач чинного дерева."""
    вих = _старі_причини(факти, ж)
    if _ПРИЧИНА in вих and ж.свідчення_одного_кольору(факти, факти["url"]):
        вих.remove(_ПРИЧИНА)
    return вих


вимір.причини = причини

if __name__ == "__main__":
    база.main()
