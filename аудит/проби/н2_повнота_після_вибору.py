"""Рядок 5826, замір: ремонт повноти ПІСЛЯ вибору (`повнота_образу.ПОВНОТА`) на записаних промптах живих прогонів.

Той самий спосіб, що `н2_повнота_до_вибору.py` (звідти — читання запису, ядро вердикта, міра `лишились`, виклик моделі), але
записи — з роллю «You finish one of them» (спроба ≥ 2, після відхиленого вибору), а розбір — гілкою мосту після вибору:
ходи (`ДОПОВНЕННЯ_V1` → `доповнити_обраний`), інакше стара форма (ОБРАЗИ_V1 → `донести_ходи_кодом`, склад — як у
відповіді), і далі `дотримати_склад` (сім'я слота вільна → річ вертається), як `міст_відповіді` перед судом.
Друкує на запис: образів у промпті; образів відповіді і скільки з них без блокера; «done-n ∉ items» (номер у
«done»/«deliberate», якого не було в образі й нема в «items»); номери ходів, що не дійшли до складу; образів, що втратили річ
без прохання (поза групою дубля) — сирим складом відповіді і після `дотримати_склад`; скільки речей додано.
Режими ті самі: без ключа — записані відповіді; `--живо` — перебудований промпт іде моделі (`MODEL_URL`, `MODEL`), відповідь
лягає в `VYVID/сирі/` (типово ../аудит/н2_замір_після); `--промпти` — ще й кладе перебудовані промпти в `VYVID/промпти/`.
Запуск із джерела/:  python3 ../аудит/проби/н2_повнота_після_вибору.py [--живо] [--промпти] <тека живих> […]"""
import collections as K, glob, hashlib, json, os, re, sys
sys.path.insert(0, ".")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
os.environ.setdefault("VYVID", os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "н2_замір_після"))
import протокол as _ПР, збирач_промптів as _ЗП, повнота_образу as ПО, суд_від_моделі as СУД
import н2_повнота_до_вибору as Н2

ВИВІД = os.environ["VYVID"]


def записи(теки):
    """(шлях, промпт dict, відповідь) кожного запису ремонту повноти після вибору."""
    for т in теки:
        for ф in sorted(glob.glob(os.path.join(т, "*", "VIDPOVIDI", "*.txt")) + glob.glob(os.path.join(т, "VIDPOVIDI", "*.txt"))):
            с = open(ф, encoding="utf8", errors="replace").read()
            г = re.match(r"── ПРОМПТ \(\d+ симв\.\) ──\n(.*)\n\n── ВІДПОВІДЬ \(([^\n]*)\) ──\n(.*)\n$", с, re.S)
            if г and "You finish one of them" in г.group(1)[:600]:
                yield ф, json.loads(г.group(1)), г.group(3)


def промпт(п, яд):
    """Той самий запис, зібраний чинним `ПОВНОТА`: діра несе `options` з вітрини запису, `still_missing` — як у записі."""
    позиція = {р["n"]: і for і, р in enumerate(п.get("showcase") or [])}
    вердикт = json.loads(json.dumps(п["verdict"]))
    for в, о in zip(вердикт, яд["образи"]):
        for б, бя in zip(в["structure"]["blockers"], о["структура"]["блокери"]):
            вар = sorted(ПО._варіанти_блокера(бя, яд["вітрина"]), key=lambda н: позиція.get(н, len(позиція)))
            if вар:
                б["options"] = вар
    дані = {к: п[к] for к in ("case", "day", "showcase", "still_missing", "she_refuses") if п.get(к)}
    return json.dumps(_ЗП.зібрати(ПО.ПОВНОТА, dict(дані, verdict=вердикт), мова_тексту="English"),
                      ensure_ascii=False, separators=(",", ":"))


def дотримати(склад, яд, описи):
    """`дотримати_склад` над складами відповіді: номер — і id, і номер (`ном`), слот — з `type` речі дроту."""
    ном = {н: (int(н[1:].split("·")[0]), н.split("·")[1]) for о in яд["образи"] for н in о["речі"]}
    слов = {н: dict(слот=Н2.слот(описи.get(н) or {"type": "?"}), назва=(описи.get(н) or {}).get("name")) for н in описи}
    іди = list(склад)
    набори, _пов = ПО.дотримати_склад([[н.split("/")[0] for н in склад[і]] for і in іди],
                                      dict(образи=[dict(ід=о["ід"], речі=о["речі"]) for о in яд["образи"]]), ном, слов)
    return dict(zip(іди, набори)), len(_пов)


def розбір(відп, яд):
    """Відповідь → (склад за ід образу відповіді, номери ходів поза складом, «done-n ∉ items», форма)."""
    дп = _ПР.розбір_за_схемою(відп, "ДОПОВНЕННЯ_V1")[0]
    # ДО (main без рядка 5826) `доповнити_обраний` нема — та сама проба міряє й ДО
    дп = getattr(ПО, "доповнити_обраний", lambda *_: None)(дп, яд) if isinstance(дп, dict) else None
    if дп:
        об, форма = дп[0], "ходи"
    else:
        об = _ПР.розбір_за_схемою(відп, "ОБРАЗИ_V1")[0]
        об = (ПО.донести_ходи_кодом(об, яд) or об) if isinstance(об, dict) else None
        форма = "образи" if об else "нічого"
    було = {о["ід"]: set(о["речі"]) for о in яд["образи"]}
    склад = {str(о.get("ід")): [str(r) for r in о.get("речі") or []]
             for о in ((об or {}).get("образи") or []) if isinstance(о, dict) and str(о.get("ід")) in було}
    done = sum(bool(set(Н2.НОМЕР.findall(json.dumps([о.get("виконано"), о.get("свідомо")], ensure_ascii=False)))
                    - set(склад.get(str(о.get("ід")), [])) - було.get(str(о.get("ід")), set()))
               for о in ((об or {}).get("образи") or []) if isinstance(о, dict)) if not дп else 0
    return склад, (дп[1]["не_з_вітрини"] if дп else []), done, форма


def main(а):
    живо, кл = "--живо" in а, "--промпти" in а
    теки = [x for x in а if not x.startswith("--")]
    os.makedirs(os.path.join(ВИВІД, "сирі"), exist_ok=True)
    Р = K.Counter()
    for ф, п, відп in записи(теки):
        яд, описи = Н2.ядро(п)
        новий = промпт(п, яд)
        ключ = hashlib.sha1(новий.encode()).hexdigest()[:12]
        if кл:
            os.makedirs(os.path.join(ВИВІД, "промпти"), exist_ok=True)
            open(os.path.join(ВИВІД, "промпти", ключ + ".json"), "w", encoding="utf8").write(новий)
        if живо:
            сира = os.path.join(ВИВІД, "сирі", ключ + ".json")
            if not os.path.exists(сира):
                ст, т, с = Н2.модель(новий)
                json.dump(dict(запис=ф, статус=ст, с=round(с, 1), відповідь=т), open(сира, "w", encoding="utf8"), ensure_ascii=False)
            відп = json.load(open(сира, encoding="utf8"))["відповідь"]
        склад, не_дійшли, done, форма = розбір(відп, яд)
        за_ід = {о["ід"]: о for о in яд["образи"]}
        групи = {о["ід"]: {x for б in о["структура"]["блокери"] for x in б["речі"]} for о in яд["образи"]}
        втр = lambda ск: sum(bool(set(за_ід[і]["речі"]) - set(ск[і]) - групи[і]) for і in ск)
        цілі, повернуто = дотримати(склад, яд, описи) if склад else ({}, 0)
        без = [і for і in цілі if not Н2.лишились(за_ід[і], цілі[і], описи)]
        додано = sum(len(set(цілі[і]) - set(за_ід[і]["речі"])) for і in цілі)
        print("%-52s промпт %6d→%6d · форма %-6s · образів %d, відповіді %d, без блокера %d · done-n∉items %d · не дійшли %d · "
              "втратили річ %d → %d (повернуто кодом %d) · додано %d" % (
                  "/".join(ф.split("/")[-3:])[:52], len(json.dumps(п, ensure_ascii=False, separators=(",", ":"))), len(новий),
                  форма, len(яд["образи"]), len(склад), len(без), done, len(не_дійшли), втр(склад), втр(цілі), повернуто, додано))
        Р.update(записів=1, відповіді=len(склад), без_блокера=len(без), done=done, не_дійшли=len(не_дійшли),
                 втратили_сирим=втр(склад), втратили=втр(цілі), додано=додано, записів_без_жодного=not без)
    print("РАЗОМ", dict(Р))


if __name__ == "__main__":
    main(sys.argv[1:])
