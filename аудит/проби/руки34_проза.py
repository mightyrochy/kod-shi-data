"""#315 (25.09): руки 3–4 на картці — скільки речей у переліку, довжина видимої прози, рядків-речей у прозі (рядок
із ≥2 комами), довжина фінального пояснення («Цей образ…» / «Цей комплект…») і чи видно на картці знаки «\\n».
Читає `картки.txt` прогону стенда (ZNIMKY). Мову не оцінює. Запуск:
python аудит/проби/руки34_проза.py <тека ZNIMKY прогону> [<тека> …]"""
import re, sys, os
sys.stdout.reconfigure(encoding="utf-8")
БС = chr(92) + "n"          # видимі на картці два знаки «\n»
print("%-28s %-5s %-7s %-7s %-8s %-8s %s" % ("прогін", "рука", "речей", "проза,", "рядків", "поясн.,", "видиме \\n"))
for тека in sys.argv[1:]:
    т = open(os.path.join(тека, "картки.txt"), encoding="utf-8").read()
    for блок in т.split("═══ картка")[1:]:
        м = re.match(r"\s*(\d) з \d · рука (\d) · речей (\d+)", блок)
        if not м or м.group(2) not in "34": continue
        рядки = блок.split("\n")[1:]
        кін = next((і for і, р in enumerate(рядки) if р.strip() == "Приміряти на себе"), len(рядки))
        поч = next((і for і, р in enumerate(рядки[:кін]) if re.match(r"\s*(Твоя річ|1\.\s)", р) or len(р) > 90), кін)
        проза = "\n".join(рядки[поч:кін]).strip()
        пп = проза.replace(БС, "\n")
        і = пп.rfind("Цей образ")
        if і < 0: і = пп.rfind("Цей комплект")
        поясн, до = (пп[і:], пп[:і]) if і >= 0 else ("", пп)
        рр = [р for р in до.split("\n") if р.count(",") >= 2]
        print("%-28s %-5s %-7s %-7d %-8d %-8d %s" % (os.path.basename(тека.rstrip("/\\"))[:28], м.group(2), м.group(3),
              len(проза), len(рр), len(поясн), "так" if БС in проза else "—"))
