"""Друкує факти читання промпту паспорта без шару проти справжнього читача, без виклику моделі."""
import json
import sys
from pathlib import Path


def головна():
    """Збирає виклик 0 і читає штучні відповіді тим самим `паспорт_з_json`, що й міст."""
    sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "джерела"))
    import паспорт_нагоди as П
    import річ_з_фото as Р
    відомий = dict(нагода="побачення", місце="ресторан_районний", дрес_код="smart_casual")
    фото = [dict(ід="ф1", ширина=600, висота=900)]
    промпт = json.loads(П.промпт_паспорта(відомий, "Іду на побачення"))
    з_фото = json.loads(П.промпт_паспорта(відомий, "Ось мої сандалі, підійдуть?", фото=фото))
    завдання = з_фото["task"]
    межі, вхід = " ".join(завдання["limits"]), " ".join(завдання["input"])
    print("1 межі:", json.dumps(dict(never_for_code="never for the app, the code" in межі,
          no_code_behind="do not mention any code or system behind them" in межі,
          фото_велить="where the code checks the colours" in вхід), ensure_ascii=False))

    def читати(відповідь, сц=відомий, ф=None):
        """Відповідь моделі → паспорт виклику 0 (`шар=False`, як `міст_вхід`)."""
        return П.паспорт_з_json(json.dumps(відповідь, ensure_ascii=False), сц, "слова", фото=ф)
    відкинуті = dict(формат="просто неба", місце="бар", тривалість_год=5, година=21, темп_c=30,
                     реєстр_людини=["класика"], вето=dict(типи=["підбори"], тканини=["шифон"],
                     принти=["горох"], кольори=["червоний"], зони=[]), відповідь_людині="Добре.")
    п = читати(відкинуті)
    print("2 схема просить:", [к for к in ("формат", "місце", "тривалість_год", "година", "темп_c", "реєстр_людини")
                               if к in промпт["task"]["answer_schema"]])
    print("2 правила про реєстр:", sum('"реєстр_людини"' in x for x in промпт["task"]["rules"]))
    print("2 узято:", json.dumps({к: п.get(к) for к in ("формат", "місце", "тривалість_год", "година",
          "темп_c", "реєстр_людини")}, ensure_ascii=False))
    print("2 не тверде:", json.dumps({к: п["вето_тверде"].get(к) for к in ("типи", "тканини", "принти")},
                                     ensure_ascii=False), "звіт:", sorted({р.split(" · ")[2] for р in п["не_взято_кодом"]}))

    рукою = dict(відомий, нагода="театр", події_руки=[dict(поле="нагода", значення="театр", джерело="hand")])
    пр = json.loads(П.промпт_паспорта(рукою, "Іду на побачення"))
    print("3 обрано:", пр["обрано"].get("нагода"), "· змінено_рукою:", пр.get("змінено_рукою"),
          "· правило 1 «her words override»:", 'her words override "обрано"' in пр["task"]["rules"][0])
    print("3 модель каже побачення → нагода:", читати(dict(нагода="побачення", відповідь_людині="Добре."), рукою)["нагода"])
    типове = dict(відомий, година=11, темп_c=18, типові_поля=["година", "темп_c"])
    пт = json.loads(П.промпт_паспорта(типове, "Іду на побачення"))
    print("3 типове_не_назване:", пт.get("типове_не_назване"), "· в обрано:", sorted(пт["обрано"]),
          "· правило 1 «only from her words or обрано»:", 'only from her words or from "обрано"' in пт["task"]["rules"][0])
    чт = читати(dict(година=20, темп_c=5, відповідь_людині="Добре."), типове)
    print("3 модель міняє типове → година, темп_c:", чт["година"], чт["темп_c"])

    питання = dict(питання_людині=["Куди йдеш?", "Де це?", "Коли?"], відповідь_людині="Добре.")
    без = dict(година=19)
    print("4 схема:", промпт["task"]["answer_schema"]["питання_людині"][0][:30],
          "· лишено зі сценарієм:", len(читати(питання)["питання_людині"]),
          "· без сценарію:", len(читати(питання, без)["питання_людині"]))
    двох = читати(dict(порада_людині="Розкажи про макіяж. Можеш і не казати.", відповідь_людині="Добре."))
    print("5 порада з двох речень:", repr(двох["порада_людині"]), (двох.get("порада_відкинуто") or {}).get("причина"),
          "· ПОРАДА_РЕЧЕНЬ_МАКС =", П.ПОРАДА_РЕЧЕНЬ_МАКС)

    схема_речі = завдання["answer_schema"]["речі_з_фото"][0]
    print("6 вид просить список item_type:", "item_type list" in схема_речі["вид"],
          "· списки_речі:", list(з_фото["списки_речі"]), "· codes у вході:", "codes" in з_фото)
    пф = читати(dict(речі_з_фото=[dict(фото="ф1", слот="взуття", вид="sandals", колір="білий")],
                     відповідь_людині="Добре."), ф=фото)
    print("6 читач приймає вид:", пф["речі_з_фото"][0]["вид"], "· усього кодів item_type:", len(Р._ВМ.ТАБЛИЦЯ["item_type"]))


if __name__ == "__main__":
    головна()
