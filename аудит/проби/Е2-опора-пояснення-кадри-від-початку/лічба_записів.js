// Мірило 16255 на записаних прогонах: кожен записаний виклик опису (`аудит/проби/**/VIDPOVIDI/*ОПИС_V1_ОПИС_ВІДПОВІДЬ_V1.txt`,
// без повторів промпту) дає число кадрів («Photo N» у промпті); справжні стадія опису й картка (`картка_без_фото.js`) ідуть
// з тим самим числом кадрів, без моделі. Друкує: образів з описом без жодного фото речей і скільки з них дістали рядок
// «опис без фото»; образів з фото — скільки дістали рядок (мусить бути 0).
// Запуск з кореня: node аудит/проби/Е2-опора-пояснення-кадри-від-початку/лічба_записів.js [шлях до збирання_руки.js]
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const {сцена, кодЗ} = require("./картка_без_фото.js");
const код = кодЗ(process.argv[2]);
const файли = [];
const обійти = д => { for (const е of fs.readdirSync(д, {withFileTypes: true})){
  const ш = path.join(д, е.name);
  if (е.isDirectory()) обійти(ш);
  else if (/\/VIDPOVIDI\/[^/]*ОПИС_V1_ОПИС_ВІДПОВІДЬ_V1\.txt$/.test(ш)) файли.push(ш); } };
обійти("аудит/проби");
const кадри = new Map();
for (const ф of файли){
  const т = fs.readFileSync(ф, "utf8"), м = /^── ПРОМПТ \(\d+ симв\.\) ──\n([\s\S]*?)\n\n── ВІДПОВІДЬ/.exec(т), пр = м ? м[1] : т;
  кадри.set(crypto.createHash("sha1").update(пр).digest("hex"), (пр.match(/^Photo \d+/gm) || []).length);
}
(async () => {
  const лік = {безФото: 0, безФотоРядок: 0, зФото: 0, зФотоРядок: 0};
  for (const н of кадри.values()){
    const р = await сцена(код, {фото: Array.from({length: н}, (_, і) => "u" + і)});
    if (н === 0){ лік.безФото++; лік.безФотоРядок += р.рядок; } else { лік.зФото++; лік.зФотоРядок += р.рядок; }
  }
  console.log("записів опису: " + файли.length + " · без повторів: " + кадри.size);
  console.log("образів з описом без жодного фото речей: " + лік.безФото + " · з рядком «опис без фото»: " + лік.безФотоРядок);
  console.log("образів з описом з фото: " + лік.зФото + " · з рядком «опис без фото»: " + лік.зФотоРядок);
})();
