"""Повтори речей ДО і ПІСЛЯ ремонту — з файлів одного прогону стенда (`VIDPOVIDI=<тека>`), наряд 25.09 п.4.

Друкує на кожну відповідь моделі з образами — ітерація 1 (`ПАКЕТ_V1 → ОБРАЗИ_V1`, 10 образів) і ремонт
(`ВЕРДИКТ_V1 → ОБРАЗИ_V1`, 5 образів): скільки образів, скільки РІЗНИХ речей у слотах «сумка» й
«верхній_шар», скільки образів мають взуття, найчастіші речі і скільки разів стоїть її закріплена річ
(`обмеження.закріплені` пакета). На кожен промпт ремонту — що несе `набір.різноманітність` (квота
K-VAR-01) і чи названо там її закріплену річ. Слот речі береться з ПУЛУ пакета, а не з назви.
Ремонт читається з пулом СВОЄЇ руки (того пакета, чиї номери має вердикт: у рук 1 і 2 різні пули й
різна нумерація) і з ВІТРИНОЮ свого промпта: речі, які код доклав на «потрібно» моделі, нумеруються
після пулу, і без вітрини проба називала їх «поза пулом» (Т-7, 25.09).
Запуск:  python аудит/проби/повтори_ремонту.py <тека VIDPOVIDI> [сід]
"""
import json, os, re, sys
from collections import Counter

тека, сід = sys.argv[1], (sys.argv[2] if len(sys.argv) > 2 else '')
def частини(ф):
    т = open(os.path.join(тека, ф), encoding='utf-8').read()
    п, _, в = т.partition('\n\n── ВІДПОВІДЬ')
    return п[п.index('\n') + 1:], (в[в.index('\n') + 1:] if '\n' in в else '')
def json_з(т):
    м = re.search(r'```(?:json)?\s*([\s\S]*?)```', т or '')
    т = (м.group(1) if м else т or '').strip()
    for с in (т, т[т.find('{'):т.rfind('}') + 1]):
        try: return json.loads(с)
        except Exception: pass
    return None
def норм(р):   # «#34·40/низ», «#237 · 12/верх» — модель дописує слот; код їх читає, проба теж
    м = re.match(r'\s*#\s*(\d+)\s*·\s*(\d+)', str(р)); return '#%s·%s' % м.groups() if м else str(р)
def образи(д):
    о = (д or {}).get('образи') if isinstance(д, dict) else None
    return [[норм(р) for р in (x.get('речі') or [])] for x in (о or []) if isinstance(x, dict)]
файли = sorted(ф for ф in os.listdir(тека) if ф.endswith('.txt') and ф.startswith('seed' + сід))
def речі_пулу(д, ключ):
    return {р['н']: (с, (р.get('назва') or '')[:34]) for с, рр in ((д or {}).get(ключ) or {}).items() for р in рр}
пули, закр = [], set()
for ф in файли:
    if 'ПАКЕТ_V1' in ф:
        д = json_з(частини(ф)[0]) or {}
        пули.append(речі_пулу(д, 'пул'))
        закр |= set((д.get('обмеження') or {}).get('закріплені') or [])
def номери_вердикта(д):
    суд = (д or {}).get('вердикт') or (д or {}).get('образи') or []
    return {str(р) for с in суд if isinstance(с, dict) for р in ((с.get('твій_образ') or с).get('речі') or [])}
назва_закр = {н: р[1] for пул in пули for н, р in пул.items() if н in закр}
print('закріплені (її річ):', sorted(закр) or '—', '·', ', '.join(назва_закр.get(н, '?') for н in sorted(закр)))
for ф in файли:
    if not ('ПАКЕТ_V1' in ф or 'ВЕРДИКТ_V1_ОБРАЗИ_V1' in ф): continue
    п, в = частини(ф)
    дп = json_з(п) or {}
    if 'ПАКЕТ_V1' in ф:
        пул = речі_пулу(дп, 'пул')
    else:
        н = номери_вердикта(дп)
        пул = dict(max(пули, key=lambda пл: len(н & set(пл))) if пули else {})
        for к, р in речі_пулу(дп, 'вітрина').items():
            пул.setdefault(к, р)
    слоти = {к: р[0] for к, р in пул.items()}; назви = {к: р[1] for к, р in пул.items()}
    if 'ВЕРДИКТ_V1_ОБРАЗИ_V1' in ф:
        наб = (дп.get('набір') or {}).get('різноманітність') or {}
        ч = str(наб.get('чому') or '')
        print('\n%s · ПРОМПТ РЕМОНТУ: різноманітність ок=%s · її річ названа: %s\n   «%s»' % (ф[:24], наб.get('ок'),
              [н for н in закр if н in ч] or 'ні', ч[:600]))
    д = json_з(в)
    if д is None:
        print('%s · %s · відповідь не читається як JSON (%d симв.; обрізана стелею виводу чи не за схемою)' % (
            ф[:24], 'РЕМОНТ' if 'ВЕРДИКТ' in ф else 'ітерація 1', len(в)))
        continue
    об = образи(д)
    лічба = Counter(р for о in об for р in о)
    різні = lambda с: len({р for о in об for р in о if слоти.get(р) == с})
    print('%s · %s · образів %d · різних сумок %d, верхніх шарів %d · із взуттям %d · її річ ×%d' % (
        ф[:24], 'РЕМОНТ' if 'ВЕРДИКТ' in ф else 'ітерація 1', len(об), різні('сумка'), різні('верхній_шар'),
        sum(any(слоти.get(р) == 'взуття' for р in о) for о in об), sum(лічба[н] for н in закр)))
    print('   найчастіші: ' + (' · '.join('%d× %s «%s» (%s)' % (к, н, назви.get(н, 'поза пулом'), слоти.get(н, '?'))
                                   for н, к in лічба.most_common(4) if к > 1) or 'повторів нема'))
