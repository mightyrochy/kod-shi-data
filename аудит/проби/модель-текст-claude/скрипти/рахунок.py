"""Мірило наряду «Модель-текст-на-Claude»: токени й ціна одного запиту жінки на мості Anthropic.

Вхід — 382 виклики моделі продукту з прогону 13.11 (`аудит/проби/живий-як-людина-1/стенд/службове/*/обміни.jsonl.gz`),
кожне тіло перетворене кодом моста (`міст_тіло.js`) і повторене через `claude -p` за підпискою (`повтор.py`).
Запит жінки — один прохід (розмова й чотири образи): 8 ситуацій × 2 проходи = 16 запитів.

Що рахує (окремо — щоб припущення було видно):
- вхід вмісту = (нових + запис кешу + читання кешу CLI) − накладні CLI (системний промпт і обгортка `claude -p`,
  виміряні крихітним запитом тієї ж моделі); міст системного промпта не шле;
- кеш моста: префікс до `cache_control` (токени виміряно тим самим способом); кеш читається, коли той самий префікс
  ≥ 512 токенів уже записав виклик, що ЗАКІНЧИВСЯ до початку цього, і востаннє вживався не раніше ніж 300 с тому
  (TTL 5 хв оновлюється читанням); інакше — запис (1,25× входу). Час — початок виклику 13.11 плюс тривалість цієї моделі.
  Між різними запитами жінок кеш не рахується (консервативно);
- ціни (сторінка цін Anthropic на 19.11, наряд): Sonnet 5.5 — $2 / $10 за млн, читання кешу $0,10, запис $2,50;
  Haiku 5.5 — $0,10 / $0,50 (промпт ≤ 100 тис.), запис $0,125, читання $0,01 (загальне правило кешу: 1,25× і 0,1×).

Запуск: python3 рахунок.py <тека даних> (у ній — `дані/` цієї проби, `сторінка.jsonl` з `сторінка.py` і копія
`журнал_моделі_продукту.jsonl` прогону 13.11 під назвою `журнал_13_11.jsonl`) → таблиця markdown у stdout і `мірило.json` поруч із даними.
"""
import json, sys, os, collections, datetime, gzip

ТЕКА = sys.argv[1]
ЦІНИ = {  # вхід, вихід, запис кешу, читання кешу — $ за млн токенів
    'claude-sonnet-5-5': (2.0, 10.0, 2.5, 0.10),
    'claude-haiku-5-5': (0.10, 0.50, 0.125, 0.01),
}
ПОВЕРХ_100К_HAIKU = (0.50, 2.50, 0.625, 0.05)
МІН_ПРЕФІКС, TTL = 512, 300.0
ЗАПИТІВ = 16


def рядки(ф):
    п = os.path.join(ТЕКА, ф)
    д = gzip.open(п + '.gz', 'rt') if not os.path.exists(п) and os.path.exists(п + '.gz') else open(п)
    return [json.loads(р) for р in д if р.strip()]


def накладні(ф):
    """крихітний запит «Reply with OK.» ≈ 6 токенів вмісту; решта — CLI"""
    з = рядки(ф)[0]
    return з['вхід_нових'] + з['вхід_кеш_запис'] + з['вхід_кеш_читання'] - 6


сторінка = {з['id']: з for з in рядки('сторінка.jsonl')}
префікс_ід = {}
for текст, іди in json.load(open(os.path.join(ТЕКА, 'префікси_ids.json'))).items():
    for і in іди:
        префікс_ід[і] = текст
префікси = sorted(set(префікс_ід.values()), key=len)
токени_префікса = {}
for з in рядки('преф_s.jsonl'):
    н = int(з['id'][-2:])
    токени_префікса[префікси[н]] = з['вхід_нових'] + з['вхід_кеш_запис'] + з['вхід_кеш_читання'] - накладні('накладні_s.jsonl')


def час(і):
    return datetime.datetime.fromisoformat(сторінка[і]['час'].replace('Z', '+00:00')).timestamp()


def рахунок(записи, модель, накл):
    ціни = ЦІНИ[модель]
    за_ситуацією = collections.defaultdict(list)
    for з in записи:
        за_ситуацією[з['id'].split('#')[0]].append(з)
    сума = collections.Counter()
    for с, зз in за_ситуацією.items():
        стан = {}  # префікс → (готовий_з, востаннє)
        for з in sorted(зз, key=lambda з: час(з['id'])):
            т0 = час(з['id'])
            вміст = з['вхід_нових'] + з['вхід_кеш_запис'] + з['вхід_кеш_читання'] - накл
            п = префікс_ід.get(з['id'])
            пт = токени_префікса.get(п, 0) if п else 0
            запис = читання = 0
            if п and пт >= МІН_ПРЕФІКС:
                ст = стан.get(п)
                if ст and ст[0] <= т0 and т0 - ст[1] <= TTL:
                    читання = пт
                    стан[п] = (ст[0], т0)
                else:
                    запис = пт
                    стан[п] = (т0 + з['с'], т0 + з['с'])
            новий = вміст - запис - читання
            ц = ПОВЕРХ_100К_HAIKU if (модель == 'claude-haiku-5-5' and вміст > 100000) else ціни
            сума['вхід'] += новий; сума['запис'] += запис; сума['читання'] += читання
            сума['вихід'] += з['вихід']; сума['думки'] += з.get('думки') or 0
            сума['usd'] += (новий * ц[0] + з['вихід'] * ц[1] + запис * ц[2] + читання * ц[3]) / 1e6
            сума['викликів'] += 1
            сума['понад_4000'] += з['вихід'] > 4000
            сума['понад_85с'] += з['с'] > 85
            сума['макс_вихід'] = max(сума['макс_вихід'], з['вихід'])
            сума['макс_с'] = max(сума['макс_с'], з['с'])
    return сума


def журнал_13_11():
    """Ті самі виклики Sonnet 5.5 13.11 (мислення — типовий effort CLI): рядки журналу стенда, звірені з
    викликами сторінки за ситуацією й секундою початку (журнал має ще 48 відкинутих спроб)"""
    ж = [json.loads(р) for р in open(os.path.join(ТЕКА, 'журнал_13_11.jsonl'))]
    за_ключем = collections.defaultdict(list)
    for р in ж:
        за_ключем[(р['прохід'], р['початок_utc'])].append(р)
    вихід = []
    for і, з in сторінка.items():
        т = datetime.datetime.fromisoformat(з['час'].replace('Z', '+00:00'))
        кл = (з['с'], т.strftime('%H:%M:%S'))
        кандидати = за_ключем.get(кл) or []
        if not кандидати:
            continue
        р = кандидати.pop(0)
        вихід.append({'id': і, 'вхід_нових': р['вхід_нових'], 'вхід_кеш_запис': р['вхід_кеш_запис'],
                      'вхід_кеш_читання': р['вхід_кеш_читання'], 'вихід': р['вихід'], 'думки': None, 'с': р['с']})
    return вихід


РЯДКИ = [('Sonnet 5.5 · effort low', 'claude-sonnet-5-5', 'sonnet_low.jsonl', 'накладні_s.jsonl'),
         ('Haiku 5.5 · effort low', 'claude-haiku-5-5', 'haiku_low.jsonl', 'накладні_h.jsonl')]
підсумок = {}
print('| модель | викликів | вхід без кешу | запис кешу | читання кешу | вихід (з них думки) | ціна запиту, $ |'
      ' запитів на $100 | вихід > 4000 | > 85 с |')
print('|---|---|---|---|---|---|---|---|---|---|')
for назва, модель, ф, накл_ф in РЯДКИ:
    зз = [з for з in рядки(ф) if з['статус'] == 'ok']
    с = рахунок(зз, модель, накладні(накл_ф))
    if с['викликів'] != 382:
        print('УВАГА:', назва, 'викликів', с['викликів'], 'з 382', file=sys.stderr)
    ціна = с['usd'] / ЗАПИТІВ
    підсумок[назва] = dict(с, ціна_запиту=ціна, запитів_на_100=100 / ціна)
    print(f"| {назва} | {с['викликів']} | {с['вхід'] / ЗАПИТІВ:,.0f} | {с['запис'] / ЗАПИТІВ:,.0f} | "
          f"{с['читання'] / ЗАПИТІВ:,.0f} | {с['вихід'] / ЗАПИТІВ:,.0f} ({с['думки'] / ЗАПИТІВ:,.0f}) | {ціна:.3f} | "
          f"{100 / ціна:,.0f} | {с['понад_4000']} | {с['понад_85с']} |")
жз = журнал_13_11()
с = рахунок(жз, 'claude-sonnet-5-5', накладні('накладні_s.jsonl'))
ціна = с['usd'] / ЗАПИТІВ
підсумок['Sonnet 5.5 · 13.11 (effort CLI)'] = dict(с, ціна_запиту=ціна, запитів_на_100=100 / ціна)
print(f"| Sonnet 5.5 · 13.11, effort CLI (довідка) | {с['викликів']} | {с['вхід'] / ЗАПИТІВ:,.0f} | {с['запис'] / ЗАПИТІВ:,.0f} | "
      f"{с['читання'] / ЗАПИТІВ:,.0f} | {с['вихід'] / ЗАПИТІВ:,.0f} (—) | {ціна:.3f} | {100 / ціна:,.0f} | "
      f"{с['понад_4000']} | {с['понад_85с']} |")
print('\nнакладні CLI (віднято):', {'sonnet': накладні('накладні_s.jsonl'), 'haiku': накладні('накладні_h.jsonl')},
      '· префікси кешу, токенів:', sorted(токени_префікса.values()))
json.dump(підсумок, open(os.path.join(ТЕКА, 'мірило.json'), 'w'), ensure_ascii=False, indent=1)
