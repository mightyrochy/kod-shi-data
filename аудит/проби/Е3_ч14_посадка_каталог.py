# -*- coding: utf-8 -*-
"""Е3-одна-величина ч14 (п.6, посадка й плече): каталог ДО → ПІСЛЯ за кожним зміненим порівнянням.

Запуск із кореня репозиторію:
    python3 аудит/проби/Е3_ч14_посадка_каталог.py                       # ПІСЛЯ: код цієї гілки
    git worktree add /tmp/до <SHA_ДО>
    python3 аудит/проби/Е3_ч14_посадка_каталог.py --код /tmp/до/джерела  # ДО: той самий скрипт на старому коді

Каталог — `джерела/каталог_повний.xml` цього клону (один і той самий для ДО й ПІСЛЯ), через живий
`bridge.виклик("запити")` стенда; модель і платні API не викликаються. Тіла: стенд і `fit.тіло` на
зрості 155/165/175 см. Перебір: перші три речі кожного крою верх × низ × взуття (по одному на рівень
халяви) і сукні × взуття — `fit.перевірити` (K-FIT-01/03/04/06, K-SHO-02, K-SIL-02) і окремо
`fit.посадка_пояса(вище=True)`; верхні шари каталогу × блейзери — `outer.ремонтопридатність`
(K-OUT-05/41/42). Синтетика: верхній шар і оверсайз-верх із шириною плеча 36/40/44 см (каталог її не
несе); смуга шкіри K-SHO-02 — виміряні («річ») халява й поділ (у каталозі краї низів — дефолт слота). Друкує лічбу (правило, сила, заяви) по кожному правилу."""
import sys, pathlib, json, collections, os, io, contextlib

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
код = pathlib.Path(sys.argv[sys.argv.index("--код") + 1]).resolve() if "--код" in sys.argv else КОРІНЬ / "джерела"
os.chdir(код); sys.path.insert(0, str(код))
import feed as Ф, bridge as B, outfit as O, composer as КМ, fit as ПС, outer as ОУ

ПРАВИЛА = ("K-FIT-01", "K-FIT-03", "K-FIT-04", "K-FIT-06", "K-SHO-02", "K-SIL-02", "K-OUT-05", "K-OUT-41", "K-OUT-42")
вх = json.load(open(код / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску(str(КОРІНЬ / "джерела" / "каталог_повний.xml")); вх["гілка"] = 0
with contextlib.redirect_stdout(io.StringIO()):
    json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
F, T_стенд, _зр, _kw = B._збірка(вх)
за = collections.defaultdict(list)
for c in кат:
    к = O.крій_речі(c)
    if к and len(за[(c.get("слот"), к)]) < 3: за[(c.get("слот"), к)].append(c)
взуття = {}
for c in кат:
    if c.get("слот") == "взуття" and c.get("халява_рівень") not in взуття: взуття[c.get("халява_рівень")] = c
блейзери = [c for c in кат if c.get("слот") == "верх" and c.get("тип") == "блейзер"][:5]
ОБХ = dict(плечі=100, груди=92, талія=74, стегна=100)
ТІЛА = [("стенд", T_стенд)] + [(str(зр), ПС.тіло(зр, ОБХ)) for зр in (155, 165, 175)]
def ключ(з):
    return (з["правило"], з["сила"], tuple(sorted({x["code"] for x in (з.get("заяви") or [])})))
def річ(c, слот, T):
    return КМ.у_річ(dict(c), слот, T)
лічба, пояс_вище, ремонт, синт = (collections.Counter() for _ in range(4))
n = 0
for _, T in ТІЛА:
    взуття_т = [річ(c, "взуття", T) for c in взуття.values()]
    верхи = [річ(c, "верх", T) for (с, _), cc in sorted(за.items()) if с == "верх" for c in cc]
    низи = [річ(c, "низ", T) for (с, _), cc in sorted(за.items()) if с == "низ" for c in cc]
    сукні = [річ(c, "сукня", T) for (с, _), cc in sorted(за.items()) if с == "сукня" for c in cc]
    набори = [[в, н, вз] for в in верхи for н in низи for вз in взуття_т] + [[с, вз] for с in сукні for вз in взуття_т]
    for речі in набори:
        n += 1
        with contextlib.redirect_stdout(io.StringIO()):
            for з in ПС.перевірити(T, речі):
                if з["правило"] in ПРАВИЛА: лічба[ключ(з)] += 1
            for з in ПС.посадка_пояса(T, речі, вище=True): пояс_вище[ключ(з)] += 1
    шари = [річ(c, "верхній_шар", T) for (с, _), cc in sorted(за.items()) if с == "верхній_шар" for c in cc]
    for ш in шари:
        for б in блейзери:
            for з in ОУ.ремонтопридатність([ш, річ(б, "верх", T)], T):
                if з["правило"] in ПРАВИЛА: ремонт[ключ(з)] += 1
    for пл in (36.0, 40.0, 44.0):
        ш = dict(шари[0], ширина_плеча_см=пл, плече=None)
        for з in ОУ.ремонтопридатність([ш], T):
            if з["правило"] in ("K-OUT-41", "K-OUT-42"): синт[ключ(з)] += 1
        в = dict(верхи[0], ширина_плеча_см=пл, крій="oversized", плече=None)
        for з in ПС.плече(T, [в]) + ПС.оверсайз(T, [в, низи[0], взуття_т[0]]): синт[ключ(з)] += 1
шкіра = collections.Counter()
for _, T in ТІЛА:
    for халява in (20.0, 30.0, 40.0, 48.0):
        for поділ in (35.0, 45.0, 55.0, 70.0):
            for тон in (None, False):
                речі = [dict(id="чоботи", слот="взуття", верх_см=халява, низ_см=0.0, край_джерело="річ"),
                        dict(id="спідниця", слот="низ", верх_см=T["висоти"]["талія"], низ_см=поділ,
                             край_джерело="річ")]
                for з in ПС.смуга_шкіри(T, речі, тон_колготи=тон): шкіра[ключ(з)] += 1
print(f"код: {код}  · тіл {len(ТІЛА)}, наборів fit {n}, блейзерів {len(блейзери)}, взуття за халявою {sorted(map(str, взуття))}")
for назва, л in (("fit.перевірити", лічба), ("посадка_пояса(вище=True)", пояс_вище),
                 ("outer.ремонтопридатність (каталог)", ремонт), ("синтетика плеча 36/40/44", синт),
                 ("синтетика K-SHO-02: халява 20/30/40/48 × поділ 35/45/55/70 × колготи None/False", шкіра)):
    print(назва + ":")
    for (п, с, к), к_ in sorted(л.items()): print(f"   {к_:6d}  {п} {с:9s} {', '.join(к) or '—'}")
