# Н-outfit-2-095: сценарій кладе `нагода` й `місце` у вихід, тож подія доходить
# до K-KOH-05. До правки подія завжди була None і «semi_formal» на весіллі
# ЗАВЖДИ діставав питання «рівень коду … залежить від типу події».
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "джерела"))
import outfit as O

ПИТАННЯ = "рівень коду"
збої = 0
def перевір(мітка, умова, факт):
    global збої
    збої += not умова
    print("%s %-52s %s" % ("✓" if умова else "✗", мітка, факт))

с = O.сценарій(місце="ресторан_високий", код="semi_formal",
               нагода="весілля_гість", година=19)
перевір("нагода й місце в виході сценарію",
        (с.get("нагода"), с.get("місце")) == ("весілля_гість", "ресторан_високий"),
        "%s / %s" % (с.get("нагода"), с.get("місце")))
_суті = lambda зн: [z["суть"] for z in зн if z.get("регістр") == "питання"]
пит = _суті(O.формальність_образу([], с))
перевір("подія названа — питання про тип події не ставиться",
        not any(ПИТАННЯ in т for т in пит), пит or "питань нема")
пит0 = _суті(O.вимоги_коду([], "semi_formal"))
перевір("події нема — питання лишається",
        any(ПИТАННЯ in т for т in пит0), пит0)
перевір("неоднозначність рахується один раз і їде полем",
        с.get("код_неоднозначний") == O.неоднозначність_коду("semi_formal", "весілля_гість"),
        (с.get("код_неоднозначний") or "")[:48] + "…")
print("ВПАЛО %d" % збої)
sys.exit(1 if збої else 0)
