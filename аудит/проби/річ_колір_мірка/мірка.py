def прочитати_tsv(шлях):
    with open(шлях, encoding="utf-8") as ф:
        return list(csv.DictReader(ф, delimiter="\t"))


def записати_tsv(шлях, рядки, поля=None):
    поля = поля or list(dict.fromkeys(к for р in рядки for к in р))
    with open(шлях, "w", encoding="utf-8", newline="") as ф:
        п = csv.DictWriter(ф, поля, delimiter="\t", lineterminator="\n", restval="")
        п.writeheader()
        п.writerows(рядки)


def мед(xs, n=2):
    xs = [x for x in xs if x is not None]
    return round(statistics.median(xs), n) if xs else None


def de(a, b):
    return Л.de2000(a, b)


def lab(hex_):
    return tuple(map(float, Л.простір.hx(hex_)))


def фішка(hex_):
    """`фішка_свотча` проби #4278; коли перенос у Манселл падає (насичені точки коду поза даними переносу) —
    найближча за ΔE2000 фішка всього атласу перебором."""
    try:
        return Ф.фішка_свотча(hex_)
    except ValueError:
        л = lab(hex_)
        усі = [(None, v, 0.0) for v in З.СВІТЛОТИ] + [(2.5 * k + 2.5, v, c) for k in range(40) for v in З.СВІТЛОТИ
                                                       for c in З.ХРОМИ]
        return min((de(л, ф), ф) for ф in усі if Ф.lab_атласу(*ф) is not None)[1]


# ─── мірка: свотчі з походженням ───
def мірка(набір):
    """[(номер, позиція, hex, походження, рядок ключа, рядок набору)] — той самий відбір, що `Л.свотчі(набір)`."""
    ключ = json.loads((ОГЛЯД / f"ключ_{набір}.json").read_text(encoding="utf-8"))["речі"]
    сайт = {р["номер"]: р for р in json.loads((САЙТ / f"sets/{набір}.json").read_text(encoding="utf-8"))["речі"]}
    результат = []
    for р in прочитати_tsv(ОГЛЯД / f"лічба_{набір}_власник.tsv"):
        н = int(р["номер"])
        if н > 40:
            continue
        п1 = р["середина_1_hex_OKLab"].split(" | ")[0]
        п2 = р["середина_2_hex_OKLab"].split(" | ")[0]
        if п1:
            пари = [(п1, "підібрано")] + ([(п2, "підібрано")] if п2 else [])
        else:
            стан = next((с for с in ("ПІСЛЯ", "ДО") if р[f"{с}_більшість"] == "п"), None)
            if not стан:
                continue
            пари = [(ключ[str(н)][стан]["hex"], f"код {стан}")]
        for поз, (h, поход) in enumerate(пари, 1):
            результат.append((н, поз, h, поход, ключ[str(н)], сайт[н], р))
    еталон = Л.свотчі(набір)
    if {(н, поз): h for н, поз, h, *_ in результат} != {(н, i + 1): h for н, hs in еталон.items() for i, h in enumerate(hs)}:
        raise SystemExit(f"{набір}: відбір мірки розійшовся з `свотчі()` звіту")
    return результат


def походження(набір, мір):
    """Скільки свотчів якого походження; точний код шляхів #4278 окремо за походженням (лише sproba2 — там tsv)."""
    за = {}
    for *_, поход, _, _, _ in [(н, п, h, x, к, с, р) for н, п, h, x, к, с, р in мір]:
        за[поход] = за.get(поход, 0) + 1
    р = {"свотчів": len(мір), "за_походженням": за, "речей_з_двома": sum(1 for н, п, *_ in мір if п == 2)}
    if набір == "sproba2":
        поход = {(н, п): x for н, п, _, x, *_ in мір}
        точний = {}
        for рядок in прочитати_tsv(ФІШКА / "лічба_кольору.tsv"):
            if рядок["набір"] != набір:
                continue
            x = поход[(int(рядок["номер"]), int(рядок["позиція"]))]
            т = точний.setdefault(рядок["шлях"], {}).setdefault(x, {"з": 0, "точний": 0})
            т["з"] += 1
            т["точний"] += рядок["точний"] in ("та сама", "сусідня")
        р["точний_код_за_походженням"] = точний
    return р


# ─── 2. зсув свотча від пікселів фото ───
def складові(свотч, піксель):
    """Свотч − піксель: ΔL*, ΔC*, Δh° (коли обидві C* > 5), ΔE2000, кроки атласу між їхніми фішками."""
    Ls, Cs, hs = lch(свотч)
    Lp, Cp, hp = lch(піксель)
    dh = ((hs - hp + 180) % 360) - 180 if min(Cs, Cp) > 5 else None
    return {"ΔL": round(Ls - Lp, 2), "ΔC": round(Cs - Cp, 2), "Δh": None if dh is None else round(dh, 1),
            "ΔE": round(de(свотч, піксель), 2)}


def поправити(піксель, dL, dC, dh):
    L, C, h = lch(піксель)
    L, C = L + dL, max(0.0, C + dC)
    h = math.radians(h + (dh or 0.0))
    return (L, C * math.cos(h), C * math.sin(h))


def знак(xs):
    """(додатних, від'ємних) і двобічне p біноміального тесту знаку."""
    п = sum(x > 0 for x in xs)
    в = sum(x < 0 for x in xs)
    n = п + в
    if not n:
        return п, в, None
    k = min(п, в)
    p = min(1.0, 2 * sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n)
    return п, в, round(p, 4)


def зсув(набір, мір):
    """Рядок на свотч × точка коду (ДО, ПІСЛЯ). Точку коду в речі з двома свотчами ставимо до ближчого з них."""
    рядки = []
    for н, поз, h, поход, к, сайт, _ in мір:
        for точка in ("ДО", "ПІСЛЯ"):
            hp = (к.get(точка) or {}).get("hex")
            if not hp:
                continue
            свотчі_речі = [x for x in мір if x[0] == н]
            if len(свотчі_речі) > 1:
                ближчий = min(свотчі_речі, key=lambda x: de(lab(x[2]), lab(hp)))
                if ближчий[1] != поз:
                    continue
            с, п = lab(h), lab(hp)
            рядок = dict(набір=набір, номер=н, позиція=поз, походження=поход, точка=точка, свотч=h, піксель=hp,
                         **складові(с, п))
            фс, фп = фішка(h), фішка(hp)
            кр = Ф.кроки(фс, фп)
            рядок.update(фішка_свотча=Ф.назва_фішки(фс), фішка_пікселя=Ф.назва_фішки(фп), кроки="/".join(map(str, кр)),
                         фішка="та сама" if sum(кр) == 0 else "сусідня" if sum(кр) == 1 else "ні",
                         той_самий="так" if h.lower() == hp.lower() else "ні")
            рядки.append(рядок)
    return рядки


def звести_зсув(рядки):
    """Для групи рядків: медіани й знак кожної складової; ΔE до й після сталої поправки (leave-one-out)."""
    if not рядки:
        return {"рядків": 0}
    о = {"рядків": len(рядки)}
    for ск in ("ΔL", "ΔC", "Δh"):
        xs = [р[ск] for р in рядки if р[ск] is not None]
        п, в, p = знак(xs)
        о[ск] = {"медіана": мед(xs), "середнє": round(statistics.fmean(xs), 2) if xs else None,
                 "SD": round(statistics.pstdev(xs), 2) if len(xs) > 1 else None, "додатних": п, "від_ємних": в,
                 "p_знаку": p, "n": len(xs)}
    після = []
    for i, р in enumerate(рядки):
        інші = рядки[:i] + рядки[i + 1:]
        dL = мед([x["ΔL"] for x in інші], 4) or 0.0
        dC = мед([x["ΔC"] for x in інші], 4) or 0.0
        dh = мед([x["Δh"] for x in інші if x["Δh"] is not None], 4) if р["Δh"] is not None else 0.0
        після.append(de(lab(р["свотч"]), поправити(lab(р["піксель"]), dL, dC, dh or 0.0)))
    о["ΔE_медіана"] = мед([р["ΔE"] for р in рядки])
    о["ΔE_медіана_після_поправки"] = мед(після)
    о["ΔE_понад_6"] = sum(р["ΔE"] > ВИДИМО for р in рядки)
    о["фішка"] = {з: sum(р["фішка"] == з for р in рядки) for з in ("та сама", "сусідня", "ні")}
    о["кроки_медіана"] = мед([sum(map(int, р["кроки"].split("/"))) for р in рядки], 1)
    return о


def якір(набір, мір):
    """Поле підбору першого проходу стартувало з визнаного свотча, інакше зі свотча, що стоїть першим на сторінці.
    Для кожного підібраного: ΔE до старту й до другого свотча коду (якого поле не показувало)."""
    рядки = []
    відп = {}
    for ф in sorted((ОГЛЯД / "результати").glob(f"ohliad-koloru-{набір}-*.txt")):
        д = json.loads(ф.read_text(encoding="utf-8"))
        if д.get("набір") == набір and not д.get("пробний") and д.get("формат", "").startswith("огляд-кольору/") \
                and "прохід" not in д:
            for в in д["відповіді"]:
                відп[в["річ"]] = в
    for н, поз, h, поход, к, сайт, _ in мір:
        if поход != "підібрано" or н not in відп:
            continue
        в = відп[н]
        св = в.get("свотчі") or {}
        if not св and "свотч" in в:
            св = в["свотч"]
        визнаний = next((с for с in сайт["свотчі"] if св.get(с["мітка"]) == "правильно"), None)
        старт = (визнаний or сайт["свотчі"][0])["hex"]
        інший = next(с["hex"] for с in сайт["свотчі"] if с["hex"] != старт) if len({с["hex"] for с in сайт["свотчі"]}) > 1 \
            else старт
        рядки.append(dict(набір=набір, номер=н, позиція=поз, свотч=h, старт=старт, інший=інший,
                          ΔE_до_старту=round(de(lab(h), lab(старт)), 2), ΔE_до_іншого=round(de(lab(h), lab(інший)), 2)))
    return рядки


# ─── 3. якої точності потребує продукт ───
def ознаки_продукту(л):
    """Входи читачів продукту з точки Lab (перелік — звіт `опис-речі-кодом`, розділ 6, `читачі_продукту.md`)."""
    L, C, h = lch(л)
    о = Л.ознаки(л)
    return {
        "світлота": "темна" if L < 45 else "світла" if L >= 70 else "середня",      # колір_річ.py:1457, 45 / 70
        "тон_визначений": "ні" if C <= Л.JND else "так",                           # колір_тон.тепло_кольору, JND
        "інтерес": "так" if C >= 18 else "ні",                                     # суд_інтерес.py:94, 18
        "гучна": "так" if C >= Л.ГУЧНИЙ_C else "ні",                               # колір_річ.py:168, 40
        "родина": "+".join(sorted(о["родини"])),                                  # колір_тон.сім_ї_кольору
        "підтон": о["підтон"],                                                    # колір_тон.тепло_кольору
        "сім_я": КР.сім_я(л),                                                     # колір_річ.py:270, 8 дуг і нейтраль
    }


def інша(ознака, а, б):
    """Ознака фішки інша, ніж у свотча; родина — як у звіті (`порівняти_ознаки`): інша, коли сімей спільних нема."""
    if ознака == "родина":
        return not set(а.split("+")) & set(б.split("+"))
    return а != б


ОЗНАКИ = ("світлота", "тон_визначений", "інтерес", "гучна", "родина", "підтон", "сім_я")


def фішки_довкола(ф, кроків=ДАЛЕКО):
    """[(фішка, кроків до неї)] атласу на відстані ≤ кроків (сума кроків осей `кроки`); фішки поза атласом — ні."""
    H, V, C = ф
    iv = З.СВІТЛОТИ.index(V)
    ic = СІТКА_C.index(C)
    Vs = [З.СВІТЛОТИ[i] for i in range(max(0, iv - кроків), min(len(З.СВІТЛОТИ), iv + кроків + 1))]
    Cs = [СІТКА_C[i] for i in range(max(0, ic - кроків), min(len(СІТКА_C), ic + кроків + 1))]
    if H is None:
        Hs = [2.5 * k + 2.5 for k in range(40)]
    else:
        Hs = [((H + 2.5 * k - 1) % 100) + 1 for k in range(-кроків, кроків + 1)]
    кандидати = {(None, v, 0.0) for v in Vs} | {(h, v, c) for h in Hs for v in Vs for c in Cs if c > 0}
    результат = []
    for к in кандидати:
        d = sum(Ф.кроки(ф, к))
        if d <= кроків and Ф.lab_атласу(*к) is not None:
            результат.append((к, d))
    return результат


def продукт(набір, мір):
    рядки = []
    for н, поз, h, поход, *_ in мір:
        с = lab(h)
        ос = ознаки_продукту(с)
        ф0 = фішка(h)
        довкола = фішки_довкола(ф0)
        р = dict(набір=набір, номер=н, позиція=поз, походження=поход, свотч=h, фішка=Ф.назва_фішки(ф0),
                 ΔE_до_фішки=round(de(с, Ф.lab_атласу(*ф0)), 2), **{f"ознака_{к}": ос[к] for к in ОЗНАКИ})
        сусіди = [(к, d) for к, d in довкола if d == 1]
        дe = [de(с, Ф.lab_атласу(*к)) for к, _ in сусіди]
        р["сусідів"] = len(сусіди)
        р["ΔE_сусіда_мін"], р["ΔE_сусіда_макс"] = round(min(дe), 2), round(max(дe), 2)
        р["сусідів_понад_6"] = sum(x > ВИДИМО for x in дe)
        ознаки_фішок = {к: ознаки_продукту(Ф.lab_атласу(*к)) for к, _ in довкола}
        for о in ОЗНАКИ:
            інші = [d for к, d in довкола if інша(о, ознаки_фішок[к][о], ос[о])]
            р[f"до_порога_{о}"] = min(інші) if інші else f">{ДАЛЕКО}"
        рядки.append(р)
    return рядки


def звести_продукт(рядки):
    о = {"свотчів": len(рядки)}
    for оз in ОЗНАКИ:
        кр = [р[f"до_порога_{оз}"] for р in рядки]
        о[оз] = {"фішка_свотча_вже_інша": sum(к == 0 for к in кр), "сусідня_міняє": sum(к == 1 for к in кр),
                 "за_2": sum(к == 2 for к in кр), "за_3": sum(к == 3 for к in кр), "далі_3": sum(isinstance(к, str) for к in кр)}
    о["будь_яка_ознака_в_межах_сусідньої"] = sum(
        any(not isinstance(р[f"до_порога_{оз}"], str) and р[f"до_порога_{оз}"] <= 1 for оз in ОЗНАКИ) for р in рядки)
    о["сусідня_помітно_різна"] = sum(р["сусідів_понад_6"] > 0 for р in рядки)
    о["усі_сусідні_помітно_різні"] = sum(р["сусідів_понад_6"] == р["сусідів"] for р in рядки)
    о["ΔE_до_фішки_медіана"] = мед([р["ΔE_до_фішки"] for р in рядки])
    о["ΔE_сусіда_мін_медіана"] = мед([р["ΔE_сусіда_мін"] for р in рядки])
    о["ΔE_сусіда_макс_медіана"] = мед([р["ΔE_сусіда_макс"] for р in рядки])
    return о


def розбіжності_на_нейтральних(прод):
    """Нинішні розбіжності підтону й хроми шляхів #4278 (середина запису проти свотча, `лічба_кольору.tsv`, sproba2):
    скільки з них — на свотчах, де тон не визначений (C* ≤ JND), і де поріг підтону чи «тон визначений» — уже в
    сусідній фішці (тон свотча визначений менше, ніж на крок атласу)."""
    за = {(р["номер"], р["позиція"]): р for р in прод if р["набір"] == "sproba2"}
    о = {}
    for рядок in прочитати_tsv(ФІШКА / "лічба_кольору.tsv"):
        if рядок["набір"] != "sproba2" or "середина_підтон" not in рядок or not рядок["середина_підтон"]:
            continue
        п = за[(int(рядок["номер"]), int(рядок["позиція"]))]
        шлях = о.setdefault(рядок["шлях"], {})
        близько = any(not isinstance(п[f"до_порога_{x}"], str) and п[f"до_порога_{x}"] <= 1
                      for x in ("підтон", "тон_визначений"))
        for оз in ("підтон", "хрома"):
            т = шлях.setdefault(оз, {"розбіжностей": 0, "тон_не_визначений": 0, "поріг_у_сусідній_фішці": 0})
            if рядок[f"середина_{оз}"] != "ні":
                continue
            т["розбіжностей"] += 1
            т["тон_не_визначений"] += п["ознака_тон_визначений"] == "ні"
            т["поріг_у_сусідній_фішці"] += близько
    return о


