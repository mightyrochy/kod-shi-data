# ─── 5. людина: другий прохід наосліп ───
def прохід2(набір, мір):
    """Черга другого проходу для сторінки: речі мірки в перемішаному порядку, скільки кольорів підбирати і старт поля
    (випадкова точка OKLCH, далі ніж ΔE2000 15 від кожного свотча коду й мірки речі)."""
    rnd = random.Random(f"{ЗЕРНО}:{набір}:прохід2")
    речі = {}
    for н, поз, h, поход, к, сайт, _ in мір:
        р = речі.setdefault(н, {"номер": н, "кольорів": 0, "заборонені": [с["hex"] for с in сайт["свотчі"]]})
        р["кольорів"] += 1
        р["заборонені"].append(h)
    порядок = sorted(речі)
    rnd.shuffle(порядок)
    черга = []
    for н in порядок:
        р = речі[н]
        while True:
            L, C, h = rnd.uniform(0.35, 0.88), rnd.uniform(0.0, 0.10), rnd.uniform(0, 2 * math.pi)
            hex_ = окЛЧ_у_hex(L, C, h)
            if hex_ and min(de(lab(hex_), lab(з)) for з in р["заборонені"]) > 15:
                break
        черга.append({"номер": н, "кольорів": р["кольорів"], "старт": hex_})
    сайт = json.loads((САЙТ / f"sets/{набір}.json").read_text(encoding="utf-8"))
    return {"набір": набір, "відбиток_набору": сайт["відбиток"], "прохід": 2,
            "пояснення": "другий прохід наосліп: лише колір речі; старт поля — випадковий, не свотч коду",
            "черга": черга}


def окЛЧ_у_hex(L, C, h):
    """OKLCH → sRGB hex тими самими формулами, що сторінка; поза sRGB — None."""
    a, b = C * math.cos(h), C * math.sin(h)
    l_ = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m_ = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s_ = (L - 0.0894841775 * a - 1.291485548 * b) ** 3
    р = [4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
         -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
         -0.0041960863 * l_ - 0.7034186147 * m_ + 1.707614701 * s_]
    if any(x < -0.0005 or x > 1.0005 for x in р):
        return None
    з = lambda x: 12.92 * x if x <= 0.0031308 else 1.055 * x ** (1 / 2.4) - 0.055
    return "#" + "".join(f"{round(255 * з(min(1, max(0, x)))):02x}" for x in р)


def людина(набір, мір):
    """Другий прохід проти першого: для свотча мірки — найближчий за ΔE2000 колір другого проходу тієї речі
    (у речі з двома — призначення з найменшою сумою ΔE). Підібрані — повторюваність підбору; свотч коду — чи
    підбір збігається з тим, що людина визнала «правильно»."""
    файли = []
    for ф in sorted((ОГЛЯД / "результати").glob("*.txt")):
        try:
            д = json.loads(ф.read_text(encoding="utf-8"))
        except ValueError:
            continue
        if д.get("формат") == "огляд-кольору/прохід-2" and д.get("набір") == набір and not д.get("пробний"):
            файли.append((ф.name, д))
    рядки = []
    for назва, д in файли:
        відп = {в["річ"]: в for в in д["відповіді"]}
        for н in sorted({x[0] for x in мір}):
            свотчі = [x for x in мір if x[0] == н]
            в = відп.get(н)
            if not в or not в.get("підібрано"):
                continue
            друге = [lab(h) for h in в["підібрано"]]
            перше = [lab(x[2]) for x in свотчі]
            if len(друге) >= len(перше):
                import itertools
                пр = min(itertools.permutations(range(len(друге)), len(перше)),
                         key=lambda п: sum(de(перше[i], друге[j]) for i, j in enumerate(п)))
            else:
                пр = [min(range(len(друге)), key=lambda j: de(п1, друге[j])) for п1 in перше]
            for (н_, поз, h, поход, *_), j in zip(свотчі, пр):
                h2 = в["підібрано"][j]
                кр = Ф.кроки(фішка(h), фішка(h2))
                р = dict(файл=назва, позначка=д.get("позначка"), набір=набір, номер=н, позиція=поз, походження=поход,
                         перше=h, друге=h2, старт=в.get("старт", ""), **складові(lab(h2), lab(h)),
                         кроки="/".join(map(str, кр)),
                         фішка="та сама" if sum(кр) == 0 else "сусідня" if sum(кр) == 1 else "ні")
                if р["старт"]:
                    р["ΔE_до_старту"] = round(de(lab(h2), lab(р["старт"])), 2)
                рядки.append(р)
    return рядки


def звести_людину(рядки):
    if not рядки:
        return "чекає голосу: нема файлу формату «огляд-кольору/прохід-2» у результати/"
    о = {}
    for група, умова in (("усі", lambda р: True), ("підібрані", lambda р: р["походження"] == "підібрано"),
                         ("свотчі_коду", lambda р: р["походження"] != "підібрано")):
        г = [р for р in рядки if умова(р)]
        if not г:
            continue
        о[група] = {"кольорів": len(г), "ΔE_медіана": мед([р["ΔE"] for р in г]),
                    "та_сама_чи_сусідня": sum(р["фішка"] in ("та сама", "сусідня") for р in г),
                    "фішка": {з: sum(р["фішка"] == з for р in г) for з in ("та сама", "сусідня", "ні")},
                    "ΔE_понад_6": sum(р["ΔE"] > ВИДИМО for р in г),
                    "ΔL_медіана": мед([р["ΔL"] for р in г]), "ΔC_медіана": мед([р["ΔC"] for р in г]),
                    "ΔE_до_старту_медіана": мед([р.get("ΔE_до_старту") for р in г])}
    о["файлів"] = sorted({р["файл"] for р in рядки})
    return о


