def середина(колір):
    к = З.розібрати_колір(колір.rsplit(" ", 1)[0] if колір.endswith("%") else колір)
    return к, Л.точка(к)


def оглядач():
    ключ = json.loads((ФІШКА / "ключ.json").read_text(encoding="utf-8"))
    а = json.loads((ФІШКА / "відповіді_А.json").read_text(encoding="utf-8"))
    а2 = json.loads((ТЕКА / "відповіді_А2.json").read_text(encoding="utf-8"))
    б = json.loads((ФІШКА / "відповіді_Б.json").read_text(encoding="utf-8"))
    рядки = []
    for т in sorted(ключ):
        for i, (x, y) in enumerate(zip(а[т]["кольори"], а2[т]["кольори"])):
            р = dict(річ=т, ключ=ключ[т], колір=i + 1, А=x, А2=y, Б=б[т]["кольори"][i] if i < len(б[т]["кольори"]) else "")
            for інший in ("А2", "Б"):
                z = р[інший]
                if not z:
                    continue
                кa, тa = середина(x)
                кz, тz = середина(z)
                фa, фz = Ф.фішки_запису(кa), Ф.фішки_запису(кz)
                if фa and фz:
                    кр = min((Ф.кроки(m, n) for m in фa for n in фz), key=lambda к: (sum(к), max(к)))
                    р[f"кроки_А_{інший}"] = "/".join(map(str, кр))
                    р[f"А_{інший}"] = "та сама" if x == z else "перетин" if sum(кр) == 0 else \
                        "сусідня" if sum(кр) == 1 else "ні"
                else:
                    р[f"А_{інший}"] = "та сама" if x == z else "без коду"
                if тa is not None and тz is not None:
                    р[f"ΔE_А_{інший}"] = round(de(тa, тz), 2)
            рядки.append(р)
    return рядки


