"""Записані відповіді #38/#39 перекладача коментаря → `мовний_шар.мова` (дві спроби, як `перекластиП`) → паспорт."""
import json, sys, pathlib
корінь, тека = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
sys.path.insert(0, str(корінь / "джерела"))
import мовний_шар as М
def відповідь(н):
    т = next(тека.glob("seed3_%02d_*.txt" % н)).read_text("utf-8")
    return т.split("── ВІДПОВІДЬ", 1)[1].split("──\n", 1)[1].strip()
вх = {"вхід": "verdict_comment", "слова": "взуття не моє, хочу без каблука і без принта",
      "речі": [{"id": "ж-04103@sezone.ua", "слот": "верх"}, {"id": "ж-07291@rito.ua", "слот": "низ"},
               {"id": "ж-09741@attico.ua", "слот": "взуття"}]}
м = lambda d: json.loads(М.мова(json.dumps(d, ensure_ascii=False)))
р1 = м(dict(вх, відповідь_моделі=відповідь(38)))
print("спроба 1:", json.dumps({к: р1.get(к) for к in ("внутрішня", "незнайомі", "причина", "повтор")}, ensure_ascii=False))
р2 = м(dict(вх, помилка_формату=р1.get("причина") or р1.get("повтор"), відповідь_моделі=відповідь(39),
            перша_відповідь=відповідь(38)))
print("спроба 2:", json.dumps({к: р2.get(к) for к in ("внутрішня", "незнайомі", "причина", "повтор")}, ensure_ascii=False))
д = м({"коментар_з": р2.get("внутрішня") or {}})
print("паспорт_з_коментаря:", json.dumps({к: д.get(к) for к in ("не_ця", "додано", "чому")}, ensure_ascii=False))
