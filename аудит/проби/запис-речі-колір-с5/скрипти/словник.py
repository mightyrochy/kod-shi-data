#!/usr/bin/env python3
"""Дані словника відтінків ядра (`джерела/ядро/дані/відтінки.json`) — з наявного словника 267 блоків ISCC–NBS
(`аудит/проби/річ_колір_модель_кодує/словник_iscc_267.tsv`: центроїд кожного блоку з того самого модуля меж, без
заглушок, з українською назвою). Нового словника нема: код відтінку — англійська назва блоку через «_», бо промпт і
дріт стилістки англійською; номер блоку, назва для людини, родина ISCC, Lab і hex центроїда — як у джерелі.
Запуск з кореня: python3 -I аудит/проби/запис-речі-колір-с5/скрипти/словник.py"""
import csv, json
from pathlib import Path

КОРІНЬ = Path(__file__).resolve().parents[4]
ДЖЕРЕЛО = КОРІНЬ / "аудит/проби/річ_колір_модель_кодує/словник_iscc_267.tsv"
ВИХІД = КОРІНЬ / "джерела/ядро/дані/відтінки.json"

відтінки = {}
for р in csv.DictReader(ДЖЕРЕЛО.open(encoding="utf-8"), delimiter="\t"):
    код = р["назва_en"].replace(" ", "_").replace("-", "_")
    відтінки[код] = {"блок": int(р["код"]), "uk": р["назва_uk"], "родина": р["родина"],
                     "lab": [round(float(р[к]), 2) for к in ("L", "a", "b")], "hex": р["hex_центроїд"]}
дані = {"про": ("Словник відтінків запису речі: 267 блоків ISCC–NBS (Kelly–Judd 1976, NBS SP 440; межі — "
                "`джерела/дані_корпусу/ISCC-NBS_вікна.txt`) з українськими назвами — словник проби "
                "`аудит/проби/річ_колір_модель_кодує/словник_iscc_267.tsv`, перенесений у дані ядра скриптом "
                "`аудит/проби/запис-речі-колір-с5/скрипти/словник.py`. Код — англійська назва блоку; кожен код — "
                "ділянка (блок) простору модуля кольору: точку (центроїд, Lab і hex) і родину читачі беруть лише "
                "з неї (корінь Річ-колір-вимір, «Інваріант ПІСЛЯ»). Hex моделі не береться."),
        "відтінки": відтінки}
рядки = ",\n".join(f"  {json.dumps(к, ensure_ascii=False)}: {json.dumps(в, ensure_ascii=False)}" for к, в in відтінки.items())
ВИХІД.write_text('{\n "про": %s,\n "відтінки": {\n%s\n }\n}\n' % (json.dumps(дані["про"], ensure_ascii=False), рядки),
                 encoding="utf-8")
assert json.loads(ВИХІД.read_text(encoding="utf-8")) == дані
print(len(відтінки), "кодів →", ВИХІД.relative_to(КОРІНЬ))
