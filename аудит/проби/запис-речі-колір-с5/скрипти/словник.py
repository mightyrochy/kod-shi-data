#!/usr/bin/env python3
"""Дані словника відтінків ядра (`джерела/ядро/дані/відтінки.json`) — з наявного словника 267 блоків ISCC–NBS
(`аудит/проби/річ_колір_модель_кодує/словник_iscc_267.tsv`: центроїд кожного блоку з того самого модуля меж, без
заглушок, з українською назвою; підказки звичною назвою — `ПІДКАЗКИ` нижче). Нового словника нема: код відтінку — англійська назва блоку через «_», бо промпт і
дріт стилістки англійською; номер блоку, назва для людини, родина ISCC, Lab і hex центроїда — як у джерелі.
Запуск з кореня: python3 -I аудит/проби/запис-речі-колір-с5/скрипти/словник.py"""
import csv, json
from pathlib import Path

КОРІНЬ = Path(__file__).resolve().parents[4]
ДЖЕРЕЛО = КОРІНЬ / "аудит/проби/річ_колір_модель_кодує/словник_iscc_267.tsv"
ВИХІД = КОРІНЬ / "джерела/ядро/дані/відтінки.json"

# Підказка звичною назвою в дужках у джерелі стояла одна на всю родину блоків («пурпурно-червоний (винний, бордовий)»
# і на яскравий блок кольору фуксії, «морська хвиля, бірюза» — і на майже чорний петроль) — людина, що судить код за
# назвою, читала яскраво-рожеве як бордове (перевірка PR #4856, ж-06045). Тепер підказка — своя для кожного блоку за
# його центроїдом (hex), звірена очима зі зразком; блок без певної звичної назви лишається з точною назвою без дужок.
ПІДКАЗКИ = {
    25: "кораловий", 26: "лососевий, кораловий", 27: "кораловий", 28: "персиковий", 29: "пудрово-персиковий",
    30: "пильна троянда", 31: "тілесний, блідо-персиковий", 32: "пудровий",
    40: "цегляний, іржавий", 41: "бордово-коричневий", 42: "рожево-коричневий", 43: "теракотовий, каштановий",
    44: "темний каштан", 54: "карамельний", 63: "тауп", 64: "темний тауп",
    74: "охра, гірчично-коричневий", 75: "горіховий", 76: "кемел, пісочний", 77: "тютюновий",
    78: "шоколадний", 80: "сіро-бежевий, тауп", 81: "темний тауп",
    92: "молочно-білий, айворі", 93: "світлий беж-грейдж", 153: "холодний молочний",
    167: "бірюзово-синій", 168: "бірюзовий", 169: "морська хвиля", 170: "петроль", 171: "світло-бірюзовий",
    172: "приглушена бірюза", 173: "морська хвиля", 174: "петроль", 175: "темний петроль", 189: "крижаний білий",
    216: "фіолетовий", 217: "бузковий", 218: "аметистовий", 219: "темно-фіолетовий", 221: "бузковий, лавандовий",
    222: "лавандовий", 224: "баклажановий", 227: "сіро-лавандовий",
    236: "пурпуровий, маджента", 237: "орхідея", 238: "сливовий", 239: "темна слива", 240: "рожево-ліловий",
    241: "сливовий", 242: "темна слива", 244: "пильний ліловий", 245: "приглушений сливовий",
    254: "фуксія", 255: "малиновий, ягідний", 256: "темно-малиновий", 257: "винний", 258: "ягідний", 259: "винний",
    260: "бордовий, темний винний", 262: "приглушений ягідний", 266: "графітовий",
}

відтінки = {}
for р in csv.DictReader(ДЖЕРЕЛО.open(encoding="utf-8"), delimiter="\t"):
    код = р["назва_en"].replace(" ", "_").replace("-", "_")
    назва = р["назва_uk"].split(" (")[0]
    if int(р["код"]) in ПІДКАЗКИ:
        назва = f"{назва} ({ПІДКАЗКИ[int(р['код'])]})"
    відтінки[код] = {"блок": int(р["код"]), "uk": назва, "родина": р["родина"],
                     "lab": [round(float(р[к]), 2) for к in ("L", "a", "b")], "hex": р["hex_центроїд"]}
дані = {"про": ("Словник відтінків запису речі: 267 блоків ISCC–NBS (Kelly–Judd 1976, NBS SP 440; межі — "
                "`джерела/дані_корпусу/ISCC-NBS_вікна.txt`) з українськими назвами — словник проби "
                "`аудит/проби/річ_колір_модель_кодує/словник_iscc_267.tsv`, перенесений у дані ядра скриптом "
                "`аудит/проби/запис-речі-колір-с5/скрипти/словник.py`. Код — англійська назва блоку; кожен код — "
                "ділянка (блок) простору модуля кольору: точку (центроїд, Lab і hex) і родину читачі беруть лише "
                "з неї (корінь Річ-колір-вимір, «Інваріант ПІСЛЯ»). Hex моделі не береться."),
        "відтінки": відтінки}
рядки = ",\n".join(f"  {json.dumps(к, ensure_ascii=False)}: {json.dumps(в, ensure_ascii=False)}" for к, в in відтінки.items())
ВИХІД.write_text('{\n "про": %s,\n "відтінки": {\n%s\n }\n}\n' % (json.dumps(дані["про"], ensure_ascii=False), рядки),
                 encoding="utf-8")
assert json.loads(ВИХІД.read_text(encoding="utf-8")) == дані
print(len(відтінки), "кодів →", ВИХІД.relative_to(КОРІНЬ))
