#!/usr/bin/env python3
"""Мірило (б), розріз за групами: частка «взята хоч раз за 20» і частка взять на рядок-запит — для речей, чий колір
був невідомий ДО (усі 179; з них переписані записом нового виду — 143, лишились без коду — 36) проти решти (376), ДО
(`аудит/звіти/стилістка-вибір-з-пулу/проба-с5`) і ПІСЛЯ (`проба/` тут). Межі — Вілсон і Ньюкомб, як `розбір_проби.py`.
Запуск з кореня: python3 аудит/проби/запис-речі-колір-с5/скрипти/розбір_груп.py"""
import importlib.util, json, sys
from pathlib import Path

КОРІНЬ = Path(__file__).resolve().parents[4]
sys.argv = [sys.argv[0], "--нічого"]
сп = importlib.util.spec_from_file_location("пп", КОРІНЬ / "аудит/проби/запис-речі-колір-с5/скрипти/проба_пул.py")
М = importlib.util.module_from_spec(сп); сп.loader.exec_module(М)
сп2 = importlib.util.spec_from_file_location("розбір", КОРІНЬ / "аудит/звіти/стилістка-вибір-з-пулу/розбір_проби.py")
Р = importlib.util.module_from_spec(сп2); sys.modules["проба"] = М.ПР; сп2.loader.exec_module(Р)

до = М.ЗАПИТ_ЗАПИСУ()
ihex = до["pool"]["cols"].index("hex")
пул = {r[0] for r in до["pool"]["rows"]}
невідомий = {r[0] for r in до["pool"]["rows"] if r[ihex] is None}
переписані = set(М.мітки_за_n()) & невідомий
групи = {"невідомий ДО — усі": невідомий, "невідомий ДО — переписаний записом": переписані,
         "невідомий ДО — без коду й ПІСЛЯ": невідомий - переписані, "решта (виміряний)": пул - невідомий}


def взяття(тека):
    вихід = []
    for ф in sorted(тека.glob("*.json")):
        o = json.loads(ф.read_text(encoding="utf-8"))
        try:
            в = М.ПР.П.розібрати_json(o["відповідь"])
            вихід.append({n for ou in в["outfits"] for x in ou["items"] if (n := М.ПР.П.номер(x)) in пул})
        except Exception:
            continue
    return вихід


підсумок = {}
for назва, тека in (("ДО", КОРІНЬ / "аудит/звіти/стилістка-вибір-з-пулу/проба-с5"), ("ПІСЛЯ", М.ПРОБА / "проба")):
    з = взяття(тека)
    хоч_раз = set().union(*з)
    рядок = {"запитів": len(з)}
    for г, ns in групи.items():
        k = len(ns & хоч_раз); взять = sum(len(ns & x) for x in з)
        рядок[г] = {"у_пулі": len(ns), "взята_хоч_раз": k, "взять_на_рядок_запит_%": round(100 * взять / (len(ns) * len(з)), 2)}
    for г in ("невідомий ДО — усі", "невідомий ДО — переписаний записом"):
        a, b = групи[г], групи["решта (виміряний)"]
        рядок[f"різниця «хоч раз», {г} − решта, п.п."] = [round(100 * x, 1) for x in Р.різниця(len(a & хоч_раз), len(a), len(b & хоч_раз), len(b))]
    підсумок[назва] = рядок
(М.ПРОБА / "проба-групи.json").write_text(json.dumps(підсумок, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
print(json.dumps(підсумок, ensure_ascii=False, indent=1))
