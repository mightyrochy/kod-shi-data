#!/usr/bin/env python3
"""Речі проходу кольору (наряд `Запис-речі-колір-мітка`, п.3): пул запиту `с5_весілля_сестри/1/7` зі звіту
`аудит/звіти/стилістка-вибір-з-пулу/` (555 рядків, `рядки.csv.gz`). Беремо всі рядки без виміряного кольору (`н_hex`=1),
що мають однозначне зіставлення з річчю (ід), і 60 рядків із виміряним кольором (зерно 20261127) для звірки; з речей без
кольору — 60 для огляду очима (мірило (а), те саме зерно). Вихід: `дані/вибірка.json`.
Запуск з кореня: python3 -I аудит/проби/запис-речі-колір-с5/скрипти/вибірка.py"""
import csv, gzip, json, random
from pathlib import Path

КОРІНЬ = Path(__file__).resolve().parents[4]
ЗАПИТ = "с5_весілля_сестри/1/7"
рядки = [р for р in csv.DictReader(gzip.open(КОРІНЬ / "аудит/звіти/стилістка-вибір-з-пулу/рядки.csv.gz", "rt", encoding="utf-8"))
         if р["запит"] == ЗАПИТ]
без = [р for р in рядки if р["н_hex"] == "1"]
з_ід = [р for р in без if р["ід"]]
виміряні = [р for р in рядки if р["н_hex"] == "0" and р["ід"]]
зерно = random.Random(20261127)
звірка = sorted(зерно.sample(виміряні, 60), key=lambda р: int(р["позиція"]))
очима = sorted(зерно.sample(з_ід, 60), key=lambda р: int(р["позиція"]))
ключі = ("позиція", "n", "ід", "тип", "колір", "hex", "колір_укр", "крамниця")
вихід = {"запит": ЗАПИТ, "рядків": len(рядки), "без_кольору": len(без), "без_кольору_без_ід": len(без) - len(з_ід),
         "речі": [dict({к: р[к] for к in ключі}, група="без_кольору", очима=р in очима) for р in з_ід]
         + [dict({к: р[к] for к in ключі}, група="звірка", очима=False) for р in звірка]}
(КОРІНЬ / "аудит/проби/запис-речі-колір-с5/дані/вибірка.json").write_text(
    json.dumps(вихід, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
print({к: в for к, в in вихід.items() if к != "речі"}, "речей:", len(вихід["речі"]), "очима:", len(очима))
