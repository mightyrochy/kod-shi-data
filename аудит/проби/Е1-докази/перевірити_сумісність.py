"""Доводить сумісність ключів на справжньому архіві та незмінність речень."""
import hashlib
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import сумісність_записів as сумісність


def перевірити():
    """Повертає лічбу заяв, прийнятих тим самим кодом до й після перейменування."""
    файл = Path(__file__).resolve().parents[1] / "б1/ДО-2710/21_б1_побачення_звично/вердикти.txt"
    підготовлені = сумісність.підготувати(файл)
    підсумок = dict(викликів=0, прийнято_до=0, прийнято_після=0)

    def обійти(вузол):
        if isinstance(вузол, list):
            for значення in вузол:
                обійти(значення)
        elif isinstance(вузол, dict):
            розмітка, відповідь = вузол.get("розмітка"), вузол.get("відповідь_моделі")
            if розмітка and isinstance(відповідь, str):
                варіанти = підготовлені.get(hashlib.sha256(відповідь.encode()).hexdigest(), [])
                if варіанти:
                    assert len(варіанти) == 1
                    підсумок["викликів"] += 1
                    for поле, текст in [("прийнято_до", відповідь), ("прийнято_після", варіанти[0]["відповідь"])]:
                        результат = сумісність.шар.прийняти_повідомлення(розмітка, текст)
                        підсумок[поле] += sum(з["стан"] == "translated" for з in результат["заяви"])
            for значення in вузол.values():
                обійти(значення)

    обійти(json.loads(файл.read_text(encoding="utf8")))
    assert підсумок["прийнято_до"] == 0 and підсумок["прийнято_після"] > 0
    старий = json.dumps([dict(key="s_old", code="same", values=dict(item="a"))])
    новий = json.dumps([dict(key="4", code="same", values=dict(item="a"))])
    інший = json.dumps([dict(key="4", code="same", values=dict(item="b"))])
    відповідь = '{"s_old":"Дослівне речення."}'
    assert json.loads(сумісність.відповідь_на_виклик(старий, новий, відповідь)) == {"4": "Дослівне речення."}
    assert json.loads(сумісність.відповідь_на_виклик(старий, інший, відповідь)) == {"s_old": "Дослівне речення."}
    інший_протокол = '```json\n{"version":"1"}\n```'
    assert сумісність.відповідь_на_виклик(старий, новий, інший_протокол) == інший_протокол
    return підсумок


if __name__ == "__main__":
    print(json.dumps(перевірити(), ensure_ascii=False))
