def рядки_k_fit_03(T, зр, зламано):
    прогін = ПЛ.зламано(["K-FIT-03"]) if зламано else None
    пр = Б.бриф(М.пакет(ознаки, T, зр, {}), T, гілка=None, прогін_руки=прогін)["правила"]
    return [(р["код"], р["рядок"], [з.get("code") for з in р.get("заява") or []]) for р in пр
            if р["код"] in ("край", "край_утримано")]


def тіло_з_похибкою(зр, обх, пох):
    """Гіпотетичне тіло: усі похибки висот і ширин — `пох` см (лише щоб показати шлях «судиться»; запису нема)."""
    T = ПС.тіло(зр, обх)
    T["похибка_висот"] = {nm: пох for nm in T["похибка_висот"]}; T["похибка_ширин"] = {nm: пох for nm in T["похибка_ширин"]}
    return T


for п, зр, обх in ТІЛА + [("стенд, гіпотеза всі похибки 0.1 см", *ТІЛА[0][1:])]:
    T = ПС.тіло(зр, обх) if "гіпотеза" not in п else тіло_з_похибкою(зр, обх, 0.1); проф = T["профіль"]
    кл, y = collections.Counter(), 2.0
    while y <= зр - 2.0:
        м = ПС.край_проти_локального(проф, y, None, ПС.похибка_висоти(T, y), T["похибка_ширин"])
        в = (м["на_максимумі"], м["важіль_є"])
        кл["судиться" if в == (True, True) else "ні" if False in в else "утримано"] += 1
        y += 1.0
    смуги = Б.смуги_краю(T)
    утр = getattr(Б, "край_утримано", lambda T_: None)(T)
