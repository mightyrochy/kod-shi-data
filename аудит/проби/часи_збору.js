const УВІМКНЕНО = process.env.CHASY === '1' || !!process.env.ZATRYMKA;
const ПРОФІЛЬ = String(process.env.ZATRYMKA || '').split(',').map(Number);
const ОДНА = process.env.ZATRYMKA_ODNA === '1';
const _слот = {};   // модель → проміс останнього обслуговування (один слот)
let _почато = false;                // затримка — лише від дотику «Зібрати образи»
const ЖУРНАЛ_МОСТА = [];           // запит прибув / заглушка відповіла (час Node, мс епохи)

/* ZATRYMKA=typy — секунди за ТИПОМ виклику, а не за розміром відповіді заглушки: її
   відповіді в рази коротші за живі (ПАКЕТ 1.1 тис. симв. проти 9–10 тис.), тож формула
   «вихід × с/симв» на заглушці занижувала б саме найдовші кроки. Числа — ОЦІНКА хмарної
   моделі з «мінімальними думками» (перший токен 1–2 с, ~200 т/с виходу на живих розмірах
   відповідей Н-1), не вимір; ZATRYMKA_MNOZHNYK=k множить усі. Тип — префікс підпису
   заглушки (`типПромпту`). */
const ТИПИ_ОЦІНКА = [['ПАКЕТ', 15], ['ВЕРДИКТ_V1→ОБРАЗИ', 9], ['ВЕРДИКТ_V1→ВИБІР', 2], ['ОПИС', 5],
  ['мовний шар: повідомлення', 4], ['мовний шар', 6], ['проза', 3], ['перелік', 2], ['JSON+проза', 3],
  ['повтор', 9]];
/* скільки заглушка «думає» над запитом: база + вхід + вихід (у секундах → мс) або за типом */
function затримкаМс(вхідСимв, вихідСимв, тип){
  if (!process.env.ZATRYMKA) return 0;
  if (process.env.ZATRYMKA === 'typy'){
    const р = ТИПИ_ОЦІНКА.find(([п]) => String(тип || '').startsWith(п));
    return Math.round(1000 * (р ? р[1] : 3) * (Number(process.env.ZATRYMKA_MNOZHNYK) || 1));
  }
  const [б, вх, вих] = [ПРОФІЛЬ[0] || 0, ПРОФІЛЬ[1] || 0, ПРОФІЛЬ[2] || 0];
  return Math.round(1000 * (б + вх * вхідСимв / 1000 + вих * вихідСимв / 1000));
}
async function почекати(модель, вхідСимв, вихідСимв, тип){
  if (!_почато) return 0;
  const з = {тип: тип || null, модель: модель || null, вхід: вхідСимв, вихід: вихідСимв, прибув: Date.now()};
  ЖУРНАЛ_МОСТА.push(з);
  const мс = затримкаМс(вхідСимв, вихідСимв, тип);
  if (!мс){ з.відповів = Date.now(); return 0; }
  const раніше = ОДНА ? (_слот[модель] || Promise.resolve()) : Promise.resolve();
  const моє = раніше.then(() => new Promise(р => setTimeout(р, мс)));
  if (ОДНА) _слот[модель] = моє.catch(() => {});
  await моє;
  з.відповів = Date.now();
  return мс;
}

/* ── ОБГОРТКИ В СТОРІНЦІ ─────────────────────────────────────────────────────
   Хто кличе: `мітка` руки ставить `ЗБ.стадії[поз]` і тим самим синхронним кроком кличе
   модель чи `містП` — проксі на масиві стадій запамʼятовує позицію до кінця кроку
   (мікрозадача). Решта подій прив'язується за текстом: промпт, який віддав міст руці
   (`промпт_ремонту`, `промпт` опису й шару, `руки[N]`), і відповідь моделі, що пішла в
   `від_моделі` полем `текст_моделі`. */
async function обгорнути(стор){
  if (!УВІМКНЕНО) return;
  _почато = true;
  await стор.evaluate(() => {
    const Ч = window.__ЧАСИ = {т0: Date.now(), події: [], поз: null};
    const П = Ч.події, тепер = () => Date.now();
    const промптПоз = new Map(), вихідПоз = new Map(), рукаПромпт = new Map();
    const ставПоз = п => { Ч.поз = п; queueMicrotask(() => { if (Ч.поз === п) Ч.поз = null; }); };
    const позРуки = р => (typeof ЗБ !== 'undefined' && ЗБ && ЗБ.ключ) ? ЗБ.ключ.indexOf(String(р)) : null;
    const запамʼятати = (т, п) => { if (п != null && т) промптПоз.set(String(т), п); };
    const позПромпта = т => {
      т = String(т || '');
      if (промптПоз.has(т)) return промптПоз.get(т);
      for (const [р, пр] of рукаПромпт) if (т === пр || т.startsWith(пр)) return позРуки(р);
      let краще = null, довж = 0;
      for (const [к, п] of промптПоз) if (к.length > довж && к.length > 200 && т.startsWith(к)) { краще = п; довж = к.length; }
      return краще;
    };
    const проксі = () => {
      if (typeof ЗБ === 'undefined' || !ЗБ || !Array.isArray(ЗБ.стадії) || ЗБ.стадії.__часи) return;
      ЗБ.стадії = new Proxy(ЗБ.стадії, {
        get: (ц, к) => (к === '__часи' ? true : ц[к]),
        set: (ц, к, з) => { ц[к] = з;
          /* рядок 222: у стані стоїть {код, числа} внутрішньої мови, не фраза —
             у журнал іде код (порожньо там, де стадія знята: кінець руки) */
          if (/^\d$/.test(String(к))){ П.push({к: 'стадія', поз: +к, т: тепер(), текст: String((з && з.код) || '')}); ставПоз(+к); }
          return true; }});
    };
    const оПоступ = window.малюватиПоступП;
    window.малюватиПоступП = function(){ try { проксі(); } catch (_) {} return оПоступ.apply(this, arguments); };
    const підпис = (ім, д) => {
      д = д || {};
      if (ім === 'від_моделі') return [д.донор ? 'донор' : '', д.вибір_речей ? 'вибір_речей' : '',
        д.ітерація ? 'іт' + д.ітерація : '', д.відповідь || '', д.спроба_повноти ? 'повнота' + д.спроба_повноти : '',
        д.перелік_речей ? 'перелік' : '', д.мова_спроба ? 'мова' + д.мова_спроба : '',
        д.текст_моделі != null ? 'відповідь ' + String(д.текст_моделі).length : ''].filter(Boolean).join(' ');
      if (ім === 'мова') return Object.keys(д).filter(к => д[к] != null).join('+');
      if (ім === 'показ') return 'речей ' + ((д.речі || []).length);
      if (ім === 'опис') return (д.без_фото_опису ? 'без фото · ' : '') + 'речей ' + ((д.речі || []).length);
      return '';
    };
    const оМіст = window.містП;
    window.містП = async function(ім, д){
      const з = {к: 'код', ім, т0: тепер(), поз: Ч.поз, що: підпис(ім, д)};
      if (з.поз == null && д && д.текст_моделі != null && вихідПоз.has(String(д.текст_моделі))) з.поз = вихідПоз.get(String(д.текст_моделі));
      П.push(з);
      try {
        const р = await оМіст.call(this, ім, д);
        try {
          if (ім === 'запити' && р && р.руки){
            for (const [рука, т] of Object.entries(р.руки)) if (т) рукаПромпт.set(рука, String(т));
          }
          for (const поле of ['промпт', 'промпт_ремонту', 'промпт_лише_вибору', 'промпт_повноти', 'промпт_мови'])
            if (р && typeof р[поле] === 'string') запамʼятати(р[поле], з.поз);
          if (р && р.вибір_речей && Array.isArray(р.вибір_речей.запити))
            р.вибір_речей.запити.forEach(x => запамʼятати(x && x.текст, з.поз));
          if (р && р.вибір_речей && р.вибір_речей.промпт_фіналу) запамʼятати(р.вибір_речей.промпт_фіналу, з.поз);
        } catch (_) {}
        return р;
      } finally { з.т1 = тепер(); }
    };
    const очікують = new Map();   // текст промпта → [події моделі, що ще не вийшли з черги]
    const модельна = (оригінал, текстЗ) => async function(){
      const т = текстЗ(arguments);
      const з = {к: 'модель', т0: тепер(), поз: Ч.поз, симв: т.length, фото: 0};
      if (з.поз == null) з.поз = позПромпта(т);
      П.push(з);
      if (!очікують.has(т)) очікують.set(т, []);
      очікують.get(т).push(з);
      try {
        const в = await оригінал.apply(this, arguments);
        const текст = Array.isArray(в) ? в.map(б => (б && б.type === 'text') ? б.text : '').join('\n') : String(в || '');
        з.вихід = текст.length;
        if (з.поз != null) вихідПоз.set(текст, з.поз);
        return в;
      } catch (e) { з.помилка = String(e).slice(0, 160); throw e; }
      finally { з.т1 = тепер(); }
    };
    window.модельП = модельна(window.модельП, а => String(а[0] || ''));
    window.модельП_блоки = модельна(window.модельП_блоки,
      а => (а[0] || []).filter(б => б && б.type === 'text').map(б => б.text).join('\n'));
    const оДзвінок = window._дзвінокП;
    window._дзвінокП = function(повідомлення, модель){
      const ост = (повідомлення || []).slice(-1)[0] || {};
      const з_ = ост.content;
      const т = typeof з_ === 'string' ? з_ : (з_ || []).filter(б => б && б.type === 'text').map(б => б.text).join('\n');
      const ч = очікують.get(т) || [];
      const з = ч.find(x => x.старт == null);
      if (з){ з.старт = тепер(); з.фото = (з_ || []).filter(б => б && б.type === 'image').length;
              з.модель = модель || null; з.разом = JSON.stringify(повідомлення || []).length; }
      return оДзвінок.apply(this, arguments);
    };
    for (const ім of ['мовоюП', 'повідомленнямП', 'питаннямиП']){
      const о = window[ім];
      window[ім] = async function(){
        const де = String(arguments[1] || ''), м = /рука (\d)/.exec(де);
        const п = м ? позРуки(м[1]) : null;
        if (п != null) ставПоз(п);
        const з = {к: 'шар', ім, де, поз: п, т0: тепер()};
        П.push(з);
        try { return await о.apply(this, arguments); } finally { з.т1 = тепер(); }
      };
    }
    /* ЧИСТИЙ ЧАС PYTHON: інтервал `містП` включає чекання чужого Python (потік один), тож
       сам `bridge.виклик` міряється зсередини — `time.time()` у Pyodide — це `Date.now()` */
    if (typeof pyodide_показу !== 'undefined' && pyodide_показу) pyodide_показу.runPython(
      'import bridge, time\n'
      + 'if not hasattr(bridge, "_часи_о"):\n'
      + '    bridge._часи_о = bridge.виклик\n'
      + '    def _в(ім, вхід):\n'
      + '        т0 = time.time()\n'
      + '        try:\n'
      + '            return bridge._часи_о(ім, вхід)\n'
      + '        finally:\n'
      + '            bridge._часи.append([ім, т0 * 1000, time.time() * 1000])\n'
      + '    bridge.виклик = _в\n'
      + 'bridge._часи = []\n');
    const оФото = window.фотоДляЗапитуП;
    window.фотоДляЗапитуП = async function(){
      const з = {к: 'фото', т0: тепер(), поз: Ч.поз};
      П.push(з);
      try { return await оФото.apply(this, arguments); } finally { з.т1 = тепер(); }
    };
  });
}

let _pythonВід = 0;   // скільки викликів Python уже названо попереднім звітом

/* python-виклики від попереднього звіту, згорнуті за іменем: «ім ×N = с (макс)» */
function _заІменем(виклики){
  const п = {};
  виклики.forEach(з => { const x = п[з[0]] = п[з[0]] || {раз: 0, с: 0, макс: 0};
    x.раз += 1; x.с += (з[2] - з[1]) / 1000; x.макс = Math.max(x.макс, (з[2] - з[1]) / 1000); });
  return Object.entries(п).sort((a, b) => b[1].с - a[1].с)
    .map(([к, x]) => к + ' ×' + x.раз + ' = ' + x.с.toFixed(1) + ' с (макс ' + x.макс.toFixed(1) + ')').join(' · ');
}
