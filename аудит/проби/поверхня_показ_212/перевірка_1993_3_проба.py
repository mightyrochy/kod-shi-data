# -*- coding: utf-8 -*-
"""Власна проба перевірки 1993-3: ДО (a14012d5) -> ПІСЛЯ (голова).

Перевіряє:
1. Інші кадри з тон=None (кадри '00' та '34' поза 11, 30, 39).
2. Дуга через 0°.
3. Невідоме поруч із виміряним (частковий вимір + слово крамниці).
Підтверджує, що ДО бачить вади, а ПІСЛЯ їх усуває.
"""
import importlib.util
import json
from pathlib import Path
import subprocess
import sys

КОРІНЬ = Path(__file__).resolve().parents[3]
ДЖЕРЕЛА = КОРІНЬ / 'джерела'
sys.path.insert(0, str(ДЖЕРЕЛА))
sys.path.insert(0, str(ДЖЕРЕЛА / 'прилади'))

import palettes as П
from поверхня_показ_212 import кадри


def завантажити_з_git(sha, файл, псевдонім):
    вміст = subprocess.check_output(['git', 'show', f'{sha}:джерела/{файл}'], cwd=КОРІНЬ)
    spec = importlib.util.spec_from_loader(псевдонім, loader=None)
    мод = importlib.util.module_from_spec(spec)
    exec(вміст, мод.__dict__)
    return мод


import колір_річ as _КОЛІР
def main():
    print("Завантаження модулів ДО (a14012d5)...")
    P_до = завантажити_з_git('a14012d5', 'surface.py', 'surface_do')
    KR_до = завантажити_з_git('a14012d5', 'колір_річ.py', 'kolir_rich_do')
    R_до = завантажити_з_git('a14012d5', 'річ_з_фото.py', 'rich_do')
    
    print("Завантаження модулів ПІСЛЯ...")
    import surface as P_після
    import колір_річ as KR_після
    import річ_з_фото as R_після
    import міст_вхід as М

    вхід = json.loads((ДЖЕРЕЛА / 'стенд_вх.json').read_text(encoding='utf-8'))
    F, T = М.збірка(М.нормалізувати_вхід(dict(вхід)))[:2]
    палітра = П.палітра_практична(F)

    # Завантаження кадрів
    кадри_словник = {}
    for з, _кадр, _маска, _арр, пікселі, _rgb in кадри(КОРІНЬ / 'аудит/проби/поверхня_212'):
        кадри_словник[з['ключ']] = пікселі

    # 1. Інші кадри з тон=None (кадри '00' і '34')
    for кадр_id in ('00', '34'):
        пікселі = кадри_словник[кадр_id]
        
        # ДО
        sys.modules['surface'] = P_до
        R_до._ПОВ = P_до
        вим_до = R_до.виміряти(пікселі, рамка=True)
        сег_до = вим_до['поверхня']['сегменти'][0]
        assert сег_до['тон'] is None, f"Кадр {кадр_id} на ДО мав би мати тон=None"
        # Вада 1 на ДО: сегмент ядра не містить колір_не_вимір
        assert 'колір_не_вимір' not in сег_до, "На ДО сегмент помилково мав колір_не_вимір"
        
        річ_до = dict(ід=кадр_id, слот='верх', вимір=вим_до)
        каталог_до = R_до.запис_каталогу(річ_до)
        # Вада 2 на ДО: каталог не позначав не-вимір кольору
        assert 'колір_не_вимір' not in каталог_до, "На ДО каталог помилково мав колір_не_вимір"
        # Вада 3 на ДО: точка_кольору повертала повну точку Lab
        точка_до = KR_до.точка_кольору(каталог_до)
        assert точка_до is not None, "На ДО точка_кольору мала б бути не None (вада)"
        # Вада 4 на ДО: палітра стверджувала стан 'у палітрі'
        палітра_до = R_до.членство_в_палітрі(_КОЛІР.точка_кольору(вим_до), палітра)
        assert палітра_до['стан'] == 'у палітрі', f"На ДО стан палітри {палітра_до['стан']}, очікувалась вада 'у палітрі'"
        # Вада 5 на ДО: суд заявляв виміряно з фото
        суд_до = R_до.вердикт(dict(річ_до, фото='ф1'), F, T)
        assert суд_до['колір'] == 'виміряно з фото', "На ДО суд заявляв виміряно з фото"
        заяви_до = [з['code'] for з in суд_до['повідомлення']['statements']]
        assert 'colour_partly_measured' not in заяви_до, "На ДО не було colour_partly_measured"

        # ПІСЛЯ
        sys.modules['surface'] = P_після
        R_після._ПОВ = P_після
        вим_після = R_після.виміряти(пікселі, рамка=True)
        сег_після = вим_після['поверхня']['сегменти'][0]
        assert сег_після['тон'] is None
        assert 'колір_не_вимір' in сег_після
        assert _КОЛІР.провенанс_кольору(сег_після)['свідок'] == 'partial_measure'

        річ_після = dict(ід=кадр_id, слот='верх', вимір=вим_після)
        каталог_після = R_після.запис_каталогу(річ_після)
        assert 'колір_не_вимір' in каталог_після
        точка_після = KR_після.точка_кольору(каталог_після)
        assert точка_після is None, "На ПІСЛЯ точка кольору мусить бути None"
        межі_після = KR_після.межі_кольору(каталог_після)
        assert межі_після[4] is None, "На ПІСЛЯ дуга тону мусить бути None"

        палітра_після = R_після.членство_в_палітрі(вим_після, палітра)
        assert палітра_після['стан'] == 'невідомо'
        assert палітра_після['частки']['тон'] is None

        суд_після = R_після.вердикт(dict(річ_після, фото='ф1'), F, T)
        assert 'частковий вимір' in суд_після['колір']
        заяви_після = [з['code'] for з in суд_після['повідомлення']['statements']]
        assert 'colour_partly_measured' in заяви_після
        print(f"Кадр {кадр_id}: ДО (вада є) -> ПІСЛЯ (усунено: точка None, палітра невідомо, colour_partly_measured)")

    # 2. Дуга через 0°
    сегмент_дуга = dict(lab=[60, 12, 0], хрома=[12, 3], тон=[350, 10], слово='рожевий')
    # На ДО ядро поверхні не додавало колір_не_вимір для сегментів
    сегмент_дуга_до = dict(сегмент_дуга)
    каталог_дуга_до = R_до.запис_каталогу(dict(ід='дуга', слот='верх', вимір=dict(lab=[60, 12, 0], поверхня=dict(сегменти=[сегмент_дуга_до]))))
    assert KR_до.точка_кольору(каталог_дуга_до) is not None, "На ДО для дуги поверталась точка Lab"
    assert KR_до.межі_кольору(каталог_дуга_до)[4] == (0.0, 0.0), "На ДО межі обчислювались з lab (0.0, 0.0) замість дуги"

    # На ПІСЛЯ
    сегмент_дуга_після = dict(сегмент_дуга)
    сегмент_дуга_після['колір_не_вимір'] = P_після.межі_сегмента(сегмент_дуга_після)
    каталог_дуга_після = R_після.запис_каталогу(dict(ід='дуга', слот='верх', вимір=dict(lab=[60, 12, 0], поверхня=dict(сегменти=[сегмент_дуга_після]), колір_не_вимір=_КОЛІР.провенанс_кольору(сегмент_дуга_після))))
    assert KR_після.точка_кольору(каталог_дуга_після) is None, "На ПІСЛЯ для дуги точка None"
    assert KR_після.межі_кольору(каталог_дуга_після)[4] == (350, 10), "На ПІСЛЯ дуга [350, 10] збережена"
    print("Дуга через 0°: ДО (lab-точка 0.0°) -> ПІСЛЯ (збережено інтервал (350, 10), точка None)")

    # 3. Невідоме поруч із виміряним
    річ_часткова = dict(id='item_partial', slot='top',
                        колір_не_вимір=P_після.межі_сегмента(dict(lab=[60, 6, 8], хрома=[10, 12], тон=None, слово='срібний')))
    річ_слово = dict(id='item_word', slot='bottom',
                     колір_не_вимір=dict(свідок='shop_word', слово='синій', вікно=[30, 40, 20, 30, [240, 260]], чому='зі слів'))

    свідок_до = KR_до.без_входу_кольору('K-COL-06', [(річ_часткова, річ_слово)], 'cannot_tell_item_is_neutral')
    свідок_після = KR_після.без_входу_кольору('K-COL-06', [(річ_часткова, річ_слово)], 'cannot_tell_item_is_neutral')

    # На ДО обидва потрапляли в colour_word_not_photo
    коди_до = [з['code'] for з in свідок_до['заяви']]
    assert 'colour_partly_measured' not in коди_до, "На ДО не було окремої заяви colour_partly_measured"
    assert коди_до[0] == 'colour_word_not_photo'
    assert len(свідок_до['заяви'][0]['values']['items']) == 2, "На ДО частковий вимір змішувався зі словом крамниці"

    # На ПІСЛЯ розділені заяви
    коди_після = [з['code'] for з in свідок_після['заяви']]
    assert 'colour_partly_measured' in коди_після, "На ПІСЛЯ мусить бути заява colour_partly_measured"
    item_ids_partly = [it['item_id'] for з in свідок_після['заяви'] if з['code'] == 'colour_partly_measured' for it in з['values']['items']]
    assert item_ids_partly == ['item_partial'], "Лише item_partial має бути у colour_partly_measured"
    item_ids_word = [it['item_id'] for з in свідок_після['заяви'] if з['code'] == 'colour_word_not_photo' for it in з['values']['items']]
    assert item_ids_word == ['item_word'], "Лише item_word має бути у colour_word_not_photo"
    print("Невідоме поруч із виміряним: ДО (змішування у colour_word_not_photo) -> ПІСЛЯ (розділено: colour_partly_measured та colour_word_not_photo)")

    print("\nВсі перевірки ДО -> ПІСЛЯ успішно пройдені!")


if __name__ == '__main__':
    main()
