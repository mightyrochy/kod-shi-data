# -*- coding: utf-8 -*-
"""зібрати_набір.py — набір сторінки огляду кольору з таблиці проби: `набір.json` для людей і `ключ.json` для лічби.

Запуск з кореня репозиторію (після `галереї.py` того самого набору — він кладе кадри в `ohliad-koloru/foto/`):
  python3 -I аудит/проби/річ_колір_огляд_людьми/зібрати_набір.py --звіт <звіт.tsv> [--запасні <звіт.tsv>] \
      --типи <типи.tsv> --ід sproba1 --назва "Спроба 1 · 40 речей" [--давній-відбиток <16 hex>]

Чому два файли. Сторінка (`ohliad-koloru/sets/<ід>.json`) бачить лише те, що людині можна показати: галерею фото речі,
тип, свотчі з нейтральними мітками, назву відтінку й кольори принта від моделі. Звідки свотч (вимір ДО чи точка ПІСЛЯ),
стан, межі, родина моделі й вердикти оглядачів лишаються в `ключ.json`: вони підказують відповідь. Порядок свотчів за
мітками «А» і «Б» — за хешем номера, щоб місце не видавало походження (той самий, що до галерей і назв, — тож мітки файлів
формату 1 читаються тим самим ключем). Галерея — `галереї_<ід>.tsv` (перший — кадр проби) без кадрів із
`галереї_вилучено.tsv` (інша річ, інший колір, розмірна сітка); кадр, якого нема у `foto/`, — посилання крамниці.
Назва відтінку — `назви.tsv`. Запасні (`--запасні`) — речі того самого зерна після 40: у наборі окремим списком
«запасні», сторінка дає їх людині замість речі з «фото невдалі». Давній відбиток (`--давній-відбиток`) ключ приймає
для файлів, зібраних до цього кроку, а сторінка переносить з нього відповіді на свотчі й підібрані кольори."""
import argparse
import csv
import hashlib
import json
import re
import sys
from pathlib import Path

КОРІНЬ = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(КОРІНЬ / "джерела"))
from словник_кольору import СЛОВО  # noqa: E402

ВІДОБРАЖЕННЯ_РОДИНИ = {"розова": "рожева"}  # словник пише «розова»; людині показуємо літературне слово
КОРЕНІ_КОЛЬОРУ = ("біл", "чорн", "сір", "червон", "бордов", "вишн", "малин", "цегл", "терак", "руд", "корал", "помаранч",
                  "персик", "жовт", "лимон", "гірчич", "золот", "хакі", "олив", "зелен", "хвой", "м'ят", "бірюз",
                  "блакит", "синій", "сині", "синь", "бузк", "фіолет", "слив", "рожев", "троянд", "пудр", "срібн",
                  "перлин", "крем", "мокко", "капуч", "смарагд", "беж", "кемел", "піщан", "пісоч", "тауп", "лате",
                  "какао", "коричн", "шоколад", "молоч", "вершк", "графіт", "екрю", "айворі", "бордо")


def прочитати_tsv(шлях):
    """Рядки TSV як словники за заголовком."""
    with open(шлях, encoding="utf-8", newline="") as ф:
        return list(csv.DictReader(ф, delimiter="\t"))


def hex_з_поля(текст):
    """Перший hex у полі `#aabbcc · слово`."""
    м = re.search(r"#[0-9a-fA-F]{6}", текст)
    return м.group(0).lower() if м else None


def код_з_поля(текст):
    """Код кольору після «·»: `#d4d9e0 · white (білий)` і `#aeadb2 · silvery · сіра` → `white`, `silvery`."""
    м = re.search(r"·\s*([a-z_]+)", текст)
    return м.group(1) if м else ""


def межі_з_поля(текст):
    """`L* 71–73, C* 0–14, тон 40–50°` → {L:[71,73], C:[0,14], тон:[40,50] чи None}."""
    if not текст.strip():
        return None
    ль = re.search(r"L\*\s*([\d.]+)[–-]([\d.]+)", текст)
    хр = re.search(r"C\*\s*([\d.]+)[–-]([\d.]+)", текст)
    тон = re.search(r"тон\s*([\d.]+)[–-]([\d.]+)", текст)
    return {"L": [float(ль.group(1)), float(ль.group(2))] if ль else None,
            "C": [float(хр.group(1)), float(хр.group(2))] if хр else None,
            "тон": [float(тон.group(1)), float(тон.group(2))] if тон else None}


def принт_слова(поле):
    """`так (white powder_pink)` → ['білий', 'пудровий'] ; `ні` → []."""
    м = re.match(r"так\s*\(([^)]*)\)", поле.strip())
    return [СЛОВО.get(к, к) for к in м.group(1).split()] if м else []


def порядок_міток(ід, номер):
    """Нейтральний порядок: чи свотч ДО стоїть першим — за хешем, не за номером."""
    return hashlib.sha256(("%s|%s" % (ід, номер)).encode()).digest()[0] % 2 == 0


def відбиток(речі, запасні=None):
    """Відбиток змісту набору: результати з іншим набором лічба відхиляє."""
    зміст = {"речі": речі, "запасні": запасні} if запасні else речі
    return hashlib.sha256(json.dumps(зміст, ensure_ascii=False, sort_keys=True).encode()).hexdigest()[:16]


def галереї(шлях, вилучено, ід, фото):
    """{номер: [файл у foto/ чи https-посилання крамниці]} у порядку галереї, без вилучених кадрів."""
    геть = {(р["номер"], р["файл"]) for р in прочитати_tsv(вилучено) if р["набір"] == ід}
    г = {}
    for р in sorted(прочитати_tsv(шлях), key=lambda р: (int(р["номер"]), int(р["порядок"] or 0))):
        if not р["порядок"] or (р["номер"], р["файл"]) in геть:
            continue
        if р["файл"] and not (фото / р["файл"]).is_file():
            sys.exit("нема кадру %s речі %s — спершу галереї.py" % (р["файл"], р["номер"]))
        г.setdefault(int(р["номер"]), []).append(р["файл"] or р["url"])
    return г


def річ_і_ключ(р, ід, типи, галерея, назви, запасна):
    """Річ набору для людей і запис ключа з рядка таблиці проби."""
    н = int(р["номер"])
    тип = типи[р["номер"]]
    if any(к in тип.lower() for к in КОРЕНІ_КОЛЬОРУ):
        sys.exit("тип речі %d містить слово кольору: %s" % (н, тип))
    if not галерея.get(н) or галерея[н][0] != Path(р["кадр"]).name:
        sys.exit("галерея речі %d не починається з кадру проби" % н)
    до, після = hex_з_поля(р["вимір_ДО"]), hex_з_поля(р["точка_ПІСЛЯ"])
    мітки = ("ДО", "ПІСЛЯ") if порядок_міток(ід, н) else ("ПІСЛЯ", "ДО")
    hexи = {"ДО": до, "ПІСЛЯ": після}
    родина = р["модель_родина"].split("·")[-1].strip()
    річ = {"номер": н, "галерея": галерея[н], "тип": тип,
           "свотчі": [{"мітка": "А", "hex": hexи[мітки[0]]}, {"мітка": "Б", "hex": hexи[мітки[1]]}],
           "модель": {"назва": назви[(ід, н)], "принт": принт_слова(р["модель_принт"])}}
    запис = {"річ": р["річ"], "мітки": {"А": мітки[0], "Б": мітки[1]},
             "ДО": {"hex": до, "код": код_з_поля(р["вимір_ДО"])},
             "ПІСЛЯ": {"hex": після, "код": код_з_поля(р["точка_ПІСЛЯ"]), "стан": р["стан_ПІСЛЯ"],
                       "межі": межі_з_поля(р.get("межі_ПІСЛЯ") or р.get("межі_виміру") or ""),
                       "межі_моделі": [ч.strip() for ч in (р.get("межі_моделі") or "").split("+") if ч.strip()]},
             "модель": {"код": р["модель_родина"].split("·")[0].strip(), "родина": родина},
             "назва": назви[(ід, н)], "фото": len(галерея[н]),
             "вердикт_оглядача_1": р.get("вердикт_оглядача_1", "")}
    if запасна:
        запис["запасна"] = True
    return річ, запис


def головна():
    """Читає таблиці, типи, галереї й назви, пише набір і ключ."""
    п = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    тека = Path(__file__).resolve().parent
    п.add_argument("--звіт", required=True)
    п.add_argument("--запасні", default=None)
    п.add_argument("--типи", required=True)
    п.add_argument("--ід", required=True)
    п.add_argument("--назва", required=True)
    п.add_argument("--галереї", default=None, help="за замовчуванням галереї_<ід>.tsv тут")
    п.add_argument("--вилучено", default=str(тека / "галереї_вилучено.tsv"))
    п.add_argument("--назви", default=str(тека / "назви.tsv"))
    п.add_argument("--давній-відбиток", dest="давні", action="append", default=[])
    п.add_argument("--вихід", default=str(КОРІНЬ / "ohliad-koloru"))
    п.add_argument("--ключ", default=None)
    а = п.parse_args()
    типи = {r["номер"]: r["тип"].strip() for r in прочитати_tsv(а.типи)}
    назви = {(r["набір"], int(r["номер"])): r["назва"].strip() for r in прочитати_tsv(а.назви)}
    вихід = Path(а.вихід)
    (вихід / "sets").mkdir(parents=True, exist_ok=True)
    галерея = галереї(а.галереї or тека / ("галереї_%s.tsv" % а.ід), а.вилучено, а.ід, вихід / "foto")
    речі, запасні, ключ = [], [], {}
    for шлях, список, запасна in ((а.звіт, речі, False), (а.запасні, запасні, True)):
        for р in (прочитати_tsv(шлях) if шлях else []):
            річ, запис = річ_і_ключ(р, а.ід, типи, галерея, назви, запасна)
            список.append(річ)
            ключ[str(річ["номер"])] = запис
    вмст = {"id": а.ід, "назва": а.назва, "основа": "foto/", "речі": речі}
    if запасні:
        вмст["запасні"] = запасні
    вмст["відбиток"] = відбиток(речі, запасні)
    if а.давні:
        вмст["відбитки_давні"] = а.давні
    (вихід / "sets" / (а.ід + ".json")).write_text(json.dumps(вмст, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    шлях_ключа = Path(а.ключ) if а.ключ else тека / ("ключ_" + а.ід + ".json")
    шлях_ключа.write_text(json.dumps({"id": а.ід, "відбиток": вмст["відбиток"],
                                      "відбитки_приймає": [вмст["відбиток"]] + а.давні, "речі": ключ},
                                     ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    # вилучені кадри, яких не бере жоден набір, — геть з foto/ (`галереї.py` кладе всю галерею каталогу)
    усі = set()
    for ш in (вихід / "sets").glob("*.json"):
        н = json.loads(ш.read_text(encoding="utf-8"))
        for р in н["речі"] + н.get("запасні", []):
            усі.update(р.get("галерея") or [р.get("фото")])
    зайві = [вихід / "foto" / ф for ф in {р["файл"] for р in прочитати_tsv(а.вилучено)}
             if ф not in усі and (вихід / "foto" / ф).is_file()]
    for ф in зайві:
        ф.unlink()
    print("речей: %d, запасних %d, кадрів у галереях %d, відбиток %s; зайвих кадрів прибрано %d" % (
        len(речі), len(запасні), sum(len(р["галерея"]) for р in речі + запасні), вмст["відбиток"], len(зайві)))


if __name__ == "__main__":
    головна()
