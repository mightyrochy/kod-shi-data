# -*- coding: utf-8 -*-
"""лічба.py — файли результатів сторінки огляду кольору → таблиця «на кожну річ» і підсумок «хто правий: код чи модель».

Запуск з кореня репозиторію (стандартна бібліотека + `джерела/colorspace.py`, `джерела/surface.py`):
  python3 -W ignore аудит/проби/річ_колір_огляд_людьми/лічба.py [--набір <ід>] [--результати <тека>] [--ключ <ключ.json>] [--таблиця <файл.tsv>]
Набір — за ідом (`sproba1`, `sproba2`…): ключ `ключ_<ід>.json` поряд зі скриптом; у спільній теці результатів файли
інших наборів мовчки пропускаються, тож кожен набір лічать окремо тією самою текою.
Файли — `*.txt` і `*.json` у теці (текст із повідомлення, вставлений у файл, теж годиться: береться від першої «{» до
останньої «}»). Пробні (`"пробний": true`) пропускаються без `--з-пробними`; неповні — без `--неповні`; файл того ж
набору з іншим відбитком — з поясненням.

Правила лічби (рішення 08.11 за словом власника 08.11 15:03 UTC; правки правил — менеджер):
- Голос людини за свотч чи слово: «правильно» / «неправильно»; «не можу сказати» не голосує, а лічиться окремо.
  Правда — більшість серед голосів (порівну — не правильна; `--строго` рахує «не можу» проти). Розбіжність людей
  (є і «правильно», і «неправильно») — окремо, як шум огляду.
- Колір речі — середина підібраних кольорів у OKLab (по місцях: перший колір, другий); без підібраного — свотч, який
  більшість визнала правильним. Розкид — найбільша відстань OKLab (×100) від середини до підібраного.
- «Код збігається» — слово вікна коду (`surface.слово_з_lab`) для кольору речі дорівнює слову коду точки.
- ДО правильний: свотч ДО визнано і код ДО збігається. (А) спроби 1: свотч ПІСЛЯ визнано і код точки збігається.
  (Б): для «певний» — як (А); для «не певний» — межі обох прочитань містять колір речі (межі виміру, а коли ключ
  має `межі_моделі` — ще й родини моделі: слово вікна коду кольору речі лежить в одній з них) і родина моделі визнана.
  Точка без коду («не певний» спроби 2) у (А) не правильна: код не збігається.
  Допуски — аргументи; за замовчуванням ±0,5 на L* і C* (округлення в таблиці) і ±15° на тоні.
- Модель правильна — слово родини визнано. Речі, де правди нема (усі «не можу сказати» без підібраного), у лічбі
  «невизначено» й не правильні."""
import argparse
import csv
import json
import math
import sys
from collections import Counter
from pathlib import Path

КОРІНЬ = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(КОРІНЬ / "джерела"))
import colorspace as CS  # noqa: E402
import surface  # noqa: E402
from словник_кольору import СЛОВО, СІМ_Я  # noqa: E402

СЛОВА_В_КОД = {"правильно": "п", "неправильно": "н", "не можу сказати": "з"}
ФОРМАТ = "огляд-кольору/1"


# ---------- колір: OKLab вперед — з репозиторію, назад — тут (перевіряється туди й назад) ----------
def oklab(hex_):
    """OKLab кольору sRGB hex — через `colorspace`."""
    return tuple(CS.to_oklab(CS.hx(hex_)))


def hex_з_oklab(лаб):
    """sRGB hex для OKLab (обернена матриця Оттосона; поза sRGB — обрізання)."""
    L, a, b = лаб
    l, m, s = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3, (L - 0.1055613458 * a - 0.0638541728 * b) ** 3, \
        (L - 0.0894841775 * a - 1.291485548 * b) ** 3
    лін = (4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s, -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
           -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s)
    кан = [min(1.0, max(0.0, с)) for с in лін]
    кан = [12.92 * с if с <= 0.0031308 else 1.055 * с ** (1 / 2.4) - 0.055 for с in кан]
    return "#" + "".join("%02x" % round(255 * с) for с in кан)


def відстань_ok(а, б):
    """Евклідова відстань OKLab ×100 (шкала `colorspace.d_ok`, ×100 для читання)."""
    return 100 * math.dist(а, б)


def середина(hexи):
    """Середина кольорів у OKLab: (hex, OKLab, розкид) чи None."""
    if not hexи:
        return None
    лаби = [oklab(h) for h in hexи]
    с = tuple(sum(л[і] for л in лаби) / len(лаби) for і in range(3))
    return hex_з_oklab(с), с, max(відстань_ok(с, л) for л in лаби)


# ---------- читання файлів ----------
def прочитати_файл(шлях):
    """Файл результатів → словник чи None (текст довкола JSON відкидається)."""
    т = Path(шлях).read_text(encoding="utf-8", errors="replace")
    поч, кін = т.find("{"), т.rfind("}")
    if поч < 0 or кін < поч:
        return None
    try:
        return json.loads(т[поч:кін + 1])
    except ValueError:
        return None


def зібрати_людей(а, ключ):
    """Файли теки → список людей (останній файл тієї самої позначки), із поясненнями про пропущені."""
    люди, зауваги = {}, []
    for ш in sorted(list(Path(а.результати).glob("*.txt")) + list(Path(а.результати).glob("*.json"))):
        д = прочитати_файл(ш)
        if not д or д.get("формат") != ФОРМАТ:
            зауваги.append("%s: не файл результатів" % ш.name)
            continue
        if д.get("набір") != ключ["id"]:
            continue
        if д.get("відбиток") != ключ["відбиток"]:
            зауваги.append("%s: інша версія набору %s (%s) — пропущено" % (ш.name, ключ["id"], д.get("відбиток")))
            continue
        if д.get("пробний") and not а.з_пробними:
            зауваги.append("%s: пробний — пропущено" % ш.name)
            continue
        if len(д.get("відповіді", [])) < len(ключ["речі"]) and not а.неповні:
            зауваги.append("%s: неповний (%d з %d) — пропущено" % (ш.name, len(д.get("відповіді", [])), len(ключ["речі"])))
            continue
        поз = д.get("позначка", ш.stem)
        if поз in люди and люди[поз]["час"] > д.get("час_utc", ""):
            зауваги.append("%s: старіший за наявний файл позначки %s" % (ш.name, поз))
            continue
        люди[поз] = {"час": д.get("час_utc", ""), "файл": ш.name, "речі": {str(в["річ"]): в for в in д["відповіді"]}}
    return люди, зауваги


# ---------- лічба за річчю ----------
def більшість(лічильник, строго, всього):
    """«п» — правда більшості; «н» — ні; «порівну»; «—» — ніхто не голосував."""
    п, н = лічильник["п"], лічильник["н"]
    if п + н == 0:
        return "—"
    if строго:
        return "п" if п > всього / 2 else ("порівну" if п == всього / 2 else "н")
    return "п" if п > н else ("порівну" if п == н else "н")


def код_збігається(hex_, код):
    """Слово вікна коду для кольору дорівнює слову коду точки."""
    return hex_ is not None and surface.слово_з_lab(CS.hx(hex_))[0] == СЛОВО.get(код, код)


def межі_містять(k_після, hex_, а):
    """Колір речі в межах обох прочитань: виміру (L*, C* з допуском округлення, тон з допуском дуги) або родин моделі."""
    межі = k_після["межі"]
    if hex_ is None or not (межі or k_після.get("межі_моделі")):
        return None
    if k_після.get("межі_моделі") and СІМ_Я.get(surface.слово_з_lab(CS.hx(hex_))[0]) in k_після["межі_моделі"]:
        return True
    if not межі:
        return False
    L, C, h = CS.lch(CS.hx(hex_))
    if межі["L"] and not (межі["L"][0] - а.допуск_lc <= L <= межі["L"][1] + а.допуск_lc):
        return False
    if межі["C"] and not (межі["C"][0] - а.допуск_lc <= C <= межі["C"][1] + а.допуск_lc):
        return False
    if межі["тон"] and C >= 10:
        a, b = межі["тон"]
        d = min(abs((h - x + 180) % 360 - 180) for x in (a, b)) if not (a <= h <= b) else 0
        if d > а.допуск_тону:
            return False
    return True


def рахувати_річ(н, k, люди, а):
    """Усі підсумки за однією річчю."""
    відп = [(п, л["речі"].get(н)) for п, л in люди.items() if л["речі"].get(н)]
    лічб = {"ДО": Counter(), "ПІСЛЯ": Counter(), "слово": Counter(), "принт": Counter()}
    підібр = [[], []]
    for _, в in відп:
        for мітка, джерело in k["мітки"].items():
            лічб[джерело][СЛОВА_В_КОД[в["свотчі"][мітка]]] += 1
        лічб["слово"][СЛОВА_В_КОД[в["слово"]]] += 1
        if "принт" in в:
            лічб["принт"][СЛОВА_В_КОД[в["принт"]]] += 1
        for і, hex_ in enumerate(в.get("підібрано", [])[:2]):
            підібр[і].append(hex_)
    т = len(відп)
    більш = {ключ_: більшість(лічб[ключ_], а.строго, т) for ключ_ in лічб}
    розб = [ключ_ for ключ_ in лічб if лічб[ключ_]["п"] and лічб[ключ_]["н"]]
    с1, с2 = середина(підібр[0]), середина(підібр[1])
    правдивий = None
    if с1:
        правдивий = с1[0]
    else:
        for дж in ("ПІСЛЯ", "ДО"):
            if більш[дж] == "п":
                правдивий = k[дж]["hex"]
                break
    р = {"люди": т, "лічб": лічб, "більш": більш, "розб": розб, "підібр": підібр, "с1": с1, "с2": с2, "правда": правдивий}
    for дж in ("ДО", "ПІСЛЯ"):
        р[дж + "_код"] = код_збігається(правдивий if правдивий else None, k[дж]["код"]) if правдивий else None
    р["ДО_правильна"] = більш["ДО"] == "п" and bool(р["ДО_код"])
    р["А_правильна"] = більш["ПІСЛЯ"] == "п" and bool(р["ПІСЛЯ_код"])
    р["межі"] = межі_містять(k["ПІСЛЯ"], правдивий, а)
    р["модель_правильна"] = більш["слово"] == "п"
    р["Б_правильна"] = р["А_правильна"] if k["ПІСЛЯ"]["стан"] == "певний" else bool(р["межі"]) and р["модель_правильна"]
    р["невизначено"] = правдивий is None
    return р


def рядок_таблиці(н, k, р):
    """Рядок таблиці за річчю."""
    def л(ключ_):
        c = р["лічб"][ключ_]
        return "%d/%d/%d" % (c["п"], c["н"], c["з"])
    def с(с_):
        return ("%s | %s" % (с_[0], " ".join("%.3f" % x for x in с_[1])), "%.1f" % с_[2]) if с_ else ("", "")
    ряд = {"номер": н, "річ": k["річ"], "людей": р["люди"],
           "ДО_п/н/з": л("ДО"), "ДО_більшість": р["більш"]["ДО"], "ПІСЛЯ_п/н/з": л("ПІСЛЯ"), "ПІСЛЯ_більшість": р["більш"]["ПІСЛЯ"],
           "слово_п/н/з": л("слово"), "слово_більшість": р["більш"]["слово"], "принт_п/н/з": л("принт"),
           "принт_більшість": р["більш"]["принт"], "розбіжність": ",".join(р["розб"]),
           "підібрано_1": " ".join(р["підібр"][0]), "середина_1_hex_OKLab": с(р["с1"])[0], "розкид_1": с(р["с1"])[1],
           "підібрано_2": " ".join(р["підібр"][1]), "середина_2_hex_OKLab": с(р["с2"])[0], "розкид_2": с(р["с2"])[1],
           "стан_ПІСЛЯ": k["ПІСЛЯ"]["стан"], "межі_містять": {True: "так", False: "ні", None: ""}[р["межі"]],
           "ДО_код_збігається": {True: "так", False: "ні", None: ""}[р["ДО_код"]],
           "ПІСЛЯ_код_збігається": {True: "так", False: "ні", None: ""}[р["ПІСЛЯ_код"]],
           "ДО_правильна": int(р["ДО_правильна"]), "А_правильна": int(р["А_правильна"]), "Б_правильна": int(р["Б_правильна"]),
           "модель_правильна": int(р["модель_правильна"]), "невизначено": int(р["невизначено"]),
           "вердикт_оглядача_1": k.get("вердикт_оглядача_1", "")}
    return ряд


def підсумок(ключ, результати, люди):
    """Рядки підсумку: скільки правильних за людьми у ДО, у спробі 1 за (А) і (Б), у моделі."""
    р = [результати[н] for н in ключ["речі"]]
    усього = len(р)
    певних = [(н, результати[н]) for н, k in ключ["речі"].items() if k["ПІСЛЯ"]["стан"] == "певний"]
    не_певних = [(н, результати[н]) for н, k in ключ["речі"].items() if k["ПІСЛЯ"]["стан"] != "певний"]
    рядки = ["Набір %s. Людей: %d (%s); речей: %d" % (ключ["id"], len(люди), ", ".join(sorted(люди)) or "—", усього),
             "ДО (вимір до кроку): правильних %d з %d" % (sum(x["ДО_правильна"] for x in р), усього),
             "Прочитання (А) (точка й код усіх): %d з %d" % (sum(x["А_правильна"] for x in р), усього),
             "Прочитання (Б) («певний» як (А), «не певний» — межі й родина моделі): %d з %d" % (sum(x["Б_правильна"] for x in р), усього),
             "  «певний» %d, з них правильних %d; «не певний» %d, з них межі містять колір речі %d, родина моделі визнана %d, обидва %d" % (
                 len(певних), sum(x["А_правильна"] for _, x in певних), len(не_певних),
                 sum(bool(x["межі"]) for _, x in не_певних), sum(x["модель_правильна"] for _, x in не_певних),
                 sum(bool(x["межі"]) and x["модель_правильна"] for _, x in не_певних)),
             "Модель (слово родини визнано): %d з %d" % (sum(x["модель_правильна"] for x in р), усього),
             "Невизначених (правди нема): %d; з розбіжністю людей: %d" % (sum(x["невизначено"] for x in р), sum(bool(x["розб"]) for x in р))]
    return рядки


def головна():
    """Читає ключ і файли, пише таблицю й підсумок."""
    а_ = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    тека = Path(__file__).resolve().parent
    а_.add_argument("--результати", default=str(тека / "результати"))
    а_.add_argument("--набір", default="sproba1")
    а_.add_argument("--ключ", default=None)
    а_.add_argument("--таблиця", default=None)
    а_.add_argument("--з-пробними", dest="з_пробними", action="store_true")
    а_.add_argument("--неповні", action="store_true")
    а_.add_argument("--строго", action="store_true")
    а_.add_argument("--допуск-lc", dest="допуск_lc", type=float, default=0.5)
    а_.add_argument("--допуск-тону", dest="допуск_тону", type=float, default=15.0)
    а = а_.parse_args()
    ключ = json.loads(Path(а.ключ or тека / ("ключ_%s.json" % а.набір)).read_text(encoding="utf-8"))
    люди, зауваги = зібрати_людей(а, ключ)
    for з in зауваги:
        print("увага:", з, file=sys.stderr)
    результати = {н: рахувати_річ(н, k, люди, а) for н, k in ключ["речі"].items()}
    рядки = [рядок_таблиці(н, ключ["речі"][н], результати[н]) for н in ключ["речі"]]
    шлях = Path(а.таблиця) if а.таблиця else None
    if шлях:
        with open(шлях, "w", encoding="utf-8", newline="") as ф:
            w = csv.DictWriter(ф, fieldnames=list(рядки[0]), delimiter="\t")
            w.writeheader()
            w.writerows(рядки)
    print("\n".join(підсумок(ключ, результати, люди)))
    print("таблиця:", шлях or "не записано (--таблиця)")


if __name__ == "__main__":
    головна()
