# -*- coding: utf-8 -*-
"""Е3-одна-величина, частина «шаблон рівнів і форма»: рівні тіла й вердикти на каталозі ДО → ПІСЛЯ.

Запуск із кореня репозиторію:
    python3 аудит/проби/Е3_шаблон_рівнів_каталог.py                       # ПІСЛЯ: код цієї гілки
    git worktree add /tmp/до <SHA_ДО>
    python3 аудит/проби/Е3_шаблон_рівнів_каталог.py --код /tmp/до/джерела  # ДО: той самий скрипт на старому коді

Каталог — `джерела/каталог_повний.xml` цього клону (один і той самий для ДО й ПІСЛЯ), через живий
`bridge.виклик("запити")` стенда; модель і платні API не викликаються. Друкує:
  1) висоти рівнів профілю (`fit.тіло`) на тілі стенда й трьох тілах гейтів;
  2) кожну річ каталогу (верх, низ, сукня, взуття — `composer.у_річ` на цьому тілі): її краї (`верх_см`, `низ_см`);
     скільки речей змінили край;
  3) вердикти посадки (`fit.перевірити`, кожна річ сама й із першим низом / верхом) і силуету
     (`silhouette.перевірити`, крої верх × низ, як ч9) — лічба (правило, сила) і перелік переходів за річчю.
`--звірити <до.json> <після.json>` — переходи за річчю (край, вердикт посадки) між двома записами.
`--вихід <файл>` — куди записати краї й вердикти кожної речі (JSON) для звірки ДО → ПІСЛЯ."""
import sys, pathlib, json, collections, os, io, contextlib


def звірити(до, після):
    """Переходи за річчю: скільки речей змінили край і вердикт посадки, за правилом і напрямом."""
    д, п = (json.load(open(ф, encoding="utf-8")) for ф in (до, після))
    зсув = collections.Counter()
    for к, в in д["краї"].items():
        н = п["краї"].get(к)
        if в != н:
            тіло, сл = к.split("|")[0], None
            зсув[тіло] += 1
    print("речей зі зміненим краєм (тіло: лічба):", dict(sorted(зсув.items())))
    пер, прикл = collections.Counter(), collections.defaultdict(list)
    for к, в in д["посадка"].items():
        н = п["посадка"].get(к)
        до_ = collections.Counter(map(tuple, в)); пі_ = collections.Counter(map(tuple, н or []))
        for пр in set(до_) | set(пі_):
            if до_[пр] != пі_[пр]:
                ключ_ = (к.split("|")[0], пр[0], пр[1], "+" if пі_[пр] > до_[пр] else "−")
                пер[ключ_] += abs(пі_[пр] - до_[пр])
                if len(прикл[ключ_]) < 3:
                    прикл[ключ_].append("%s: край %s → %s" % (к.split("|")[1], д["краї"].get(к), п["краї"].get(к)))
    print("переходи посадки за річчю (тіло · правило · сила · напрям): лічба; приклади")
    for к_, n in sorted(пер.items(), key=lambda x: tuple(map(str, x[0]))):
        print(f"   {n:5d}  {' · '.join(map(str, к_))}   e.g. {'; '.join(прикл[к_])}")
    сил = {к: (д["силует"].get(к, 0), п["силует"].get(к, 0)) for к in set(д["силует"]) | set(п["силует"])}
    змін = {к: в for к, в in сил.items() if в[0] != в[1]}
    print("силует, змінені лічби:", змін or "нема")


if "--звірити" in sys.argv:
    і = sys.argv.index("--звірити")
    звірити(sys.argv[і + 1], sys.argv[і + 2])
    sys.exit(0)

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
код = pathlib.Path(sys.argv[sys.argv.index("--код") + 1]).resolve() if "--код" in sys.argv else КОРІНЬ / "джерела"
os.chdir(код); sys.path.insert(0, str(код))
import feed as Ф, bridge as B, outfit as O, silhouette as СЛ, composer as КМ, fit as ПС

вх = json.load(open(код / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску(str(КОРІНЬ / "джерела" / "каталог_повний.xml")); вх["гілка"] = 0
with contextlib.redirect_stdout(io.StringIO()):
    json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
F, T_стенд, _зр, _kw = B._збірка(вх)
ТІЛА = [("стенд", T_стенд)] + [(п, ПС.тіло(зр, обх)) for п, зр, обх in (
    ("пісочний", 168, dict(плечі=98, груди=92, талія=72, стегна=100)),
    ("яблуко", 160, dict(плечі=104, груди=104, талія=88, стегна=112)),
    ("трикутник", 170, dict(плечі=100, груди=96, талія=84, стегна=104)))]
print(f"код: {код} · речей каталогу {len(кат)}")
for підпис, T in ТІЛА:
    print(f"рівні · {підпис} {T['зріст']:.0f} см: " + ", ".join(f"{н} {y:.1f}" for н, y, _ in T["профіль"]))


def ключ(з):
    return (з.get("правило"), з.get("сила"))


def вердикти(T, речі):
    """Мультимножина (правило, сила) посадки на цих речах."""
    with contextlib.redirect_stdout(io.StringIO()):
        return collections.Counter(ключ(з) for з in ПС.перевірити(T, речі, intent="conventional", мета="лестити"))


рез = {"краї": {}, "посадка": {}, "силует": collections.Counter()}
за_кроєм = collections.defaultdict(list)
for c in кат:
    к = O.крій_речі(c)
    if к: за_кроєм[(c.get("слот"), к)].append(c)
for підпис, T in ТІЛА:
    речі = {}
    for c in кат:
        if c.get("слот") not in ("верх", "низ", "сукня", "взуття"):
            continue
        try:
            р = КМ.у_річ(dict(c), c.get("слот"), T)
        except Exception as e:  # noqa: BLE001 — друкуємо, не ховаємо
            рез["краї"][(підпис, c.get("id"))] = ("ВИНЯТОК", type(e).__name__)
            continue
        речі[c.get("id")] = р
        рез["краї"][(підпис, c.get("id"))] = (р.get("верх_см"), р.get("низ_см"))
    перший = {сл: next((р for р in речі.values() if р.get("слот") == сл), None) for сл in ("верх", "низ")}
    for ід, р in речі.items():
        пара = [р] + ([перший["низ"]] if р.get("слот") == "верх" and перший["низ"] else
                     [перший["верх"]] if р.get("слот") == "низ" and перший["верх"] else [])
        try:
            рез["посадка"][(підпис, ід)] = sorted(вердикти(T, пара).elements())
        except Exception as e:  # noqa: BLE001
            рез["посадка"][(підпис, ід)] = [("ВИНЯТОК", type(e).__name__)]
    верхи = sorted(k for k in за_кроєм if k[0] == "верх"); низи = sorted(k for k in за_кроєм if k[0] == "низ")
    for (_, кв) in верхи:
        for (_, кн) in низи:
            пара = [КМ.у_річ(dict(за_кроєм[("верх", кв)][0]), "верх", T), КМ.у_річ(dict(за_кроєм[("низ", кн)][0]), "низ", T)]
            for z in СЛ.перевірити(T, пара, intent="conventional", мета="лестити"):
                рез["силует"][(підпис, z["правило"], z["сила"])] += 1

лічба = collections.Counter()
for (підпис, ід), в in рез["посадка"].items():
    for к in в: лічба[(підпис,) + tuple(к)] += 1
print("посадка (тіло, правило, сила): лічба")
for к, n in sorted(лічба.items(), key=lambda x: tuple(map(str, x[0]))): print(f"   {n:6d}  {' · '.join(map(str, к))}")
print("силует крої верх × низ (тіло, правило, сила): лічба")
for к, n in sorted(рез["силует"].items(), key=lambda x: tuple(map(str, x[0]))): print(f"   {n:6d}  {' · '.join(map(str, к))}")
вихід = pathlib.Path(sys.argv[sys.argv.index("--вихід") + 1] if "--вихід" in sys.argv
                     else "/tmp/е3_шаблон_рівнів_%s.json" % ("до" if "--код" in sys.argv else "після"))
вихід.write_text(json.dumps({"краї": {"%s|%s" % к: в for к, в in рез["краї"].items()},
                             "посадка": {"%s|%s" % к: в for к, в in рез["посадка"].items()},
                             "силует": {"|".join(map(str, к)): n for к, n in рез["силует"].items()}},
                            ensure_ascii=False), encoding="utf-8")
print("записано:", вихід)
