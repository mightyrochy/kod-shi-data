"""Рядок 125(г): чим ВХІД ПРИМІРЯННЯ різниться між руками — числом, не здогадом.

`показ.html:приміряти` бере `зФото = речі.filter(фото).slice(0,8)`: є фото —
режим «за фото» і до 8 знімків крамниць у запит; нема — «за описом», сама
людина. Проба міряє стелю цього числа на кожній руці.
"""
import json, os, sys, collections
ТУТ = os.path.dirname(os.path.abspath(__file__))
КОРІНЬ = os.path.dirname(os.path.dirname(ТУТ))
sys.path.insert(0, os.path.join(КОРІНЬ, "джерела"))
os.chdir(os.path.join(КОРІНЬ, "джерела"))
import bridge as B

вх = json.load(open("стенд_вх.json"))
r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
пул = [o for v in (r.get("кандидати") or {}).values() for o in v]
ід = [o["id"] for o in пул][:8]
картки = json.loads(B.виклик("показ", json.dumps({**вх, "речі": ід}, ensure_ascii=False)))
картки = картки.get("речі", картки) if isinstance(картки, dict) else картки
зфото = sum(1 for к in картки if к.get("фото"))

вигадані = ["м-сукня-1", "м-туфлі-2", "м-клатч-3", "м-сережки-4"]
к34 = json.loads(B.виклик("показ", json.dumps({**вх, "речі": вигадані}, ensure_ascii=False)))
к34 = к34.get("речі", к34) if isinstance(к34, dict) else к34
зфото34 = sum(1 for к in к34 if к.get("фото"))

print("пул речей:", r.get("пул_речей"), "· довжина промпта руки:",
      {k: len(v) for k, v in sorted((r.get("руки") or {}).items())})
for рука in ("1", "2", "3", "4"):
    каталог = рука in ("1", "2")
    n = зфото if каталог else зфото34
    print("рука %s: каталог=%s · речей з фото зі стелі 8 = %d · режим приміряння = %s"
          % (рука, "так" if каталог else "НІ", n, "за фото" if n else "за описом"))
крам = collections.Counter(str(к.get("id", "")).split("@")[-1] for к in картки if к.get("фото"))
print("крамниці знімків, що йдуть у примірку (руки 1-2):", dict(крам))
print("ВИСНОВОК: різниця входу приміряння між руками рівно одна — СКІЛЬКИ ЗОБРАЖЕНЬ")
print("  у запиті: руки 1-2 шлють 1 фото людини + до 8 знімків крамниць = до 9;")
print("  руки 3-4 шлють 1 фото людини = 1. Рядок «Речей на картинці N з N», що на")
print("  скріншоті власника, буває ЛИШЕ в режимі «за фото», тобто лише на руках 1-2.")
print("  Чим ці дві різняться між собою у приміряння — нічим: той самий `приміряти`,")
print("  той самий зріз slice(0,8), той самий промпт; різний лише СКЛАД образу,")
print("  який обирає модель, і він офлайн не міряється.")
