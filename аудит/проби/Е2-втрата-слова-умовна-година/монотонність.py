"""МІРИЛО ДОРОБКИ «суд дороги» (дошка 16198): чи слабшає знахідка K-SHO-16, коли до названого додано ще одне слово.

Входи суду ціни каблука — те, що вона може назвати: тривалість події (2 чи 8 год), дорога пішки (20 хв), поверхня
(«бруківка», та інші з `ПОВЕРХНІ`) і опади, з яких виводиться поверхня («сніг», «дощ»). Пара — набір названого А і
А + ще одне слово іншого роду; каблук — 5, 7, 9, 11 см. Сила — `сила_нп` знахідки K-SHO-16 (питання чи мовчання — 0).
Пара «слабшає», коли сила з доданим словом менша. Окремо — пари, де додане слово — поверхня з коефіцієнтом < 1
(«паркет», «килим»): там знахідка слабшає через таблицю коефіцієнтів без джерела (дошка 16200), а не через умовну
тривалість.

Запуск з кореня репозиторію: `python3 аудит/проби/Е2-втрата-слова-умовна-година/монотонність.py`."""
import itertools, os, sys
КОРІНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
sys.path.insert(0, os.path.join(КОРІНЬ, 'джерела'))
os.chdir(os.path.join(КОРІНЬ, 'джерела'))
import аксесуари_носіння as АН

РОДИ = dict(тривалість_год=(2, 8), дорога_пішки_хв=(20,), поверхня=tuple(АН.ПОВЕРХНІ), опади=('сніг', 'дощ'))
М_ЯКІ = {п for п, к in АН.ПОВЕРХНІ.items() if к < 1.0}


def сила(h, вх):
    зн = АН.вартість_носіння([dict(id='x', назва='пара', слот='взуття', каблук_см=h)], **вх)
    с = [(з.get('сила_нп') or 0.0, з['сила']) for з in зн if з['правило'] == 'K-SHO-16' and з['сила'] != 'питання']
    return max(с) if с else (0.0, 'питання' if зн else '—')


def набори():
    роди = list(РОДИ)
    for к in range(len(роди) + 1):
        for вибір in itertools.combinations(роди, к):
            for знач in itertools.product(*(РОДИ[р] for р in вибір)):
                yield dict(zip(вибір, знач))


підсумок = {}
приклади = {}
for h in (5, 7, 9, 11):
    for А in набори():
        сА = сила(h, А)
        for рід in РОДИ:
            if рід in А:
                continue
            for з in РОДИ[рід]:
                Б = dict(А, **{рід: з})
                сБ = сила(h, Б)
                група = 'поверхня з коефіцієнтом < 1 (16200)' if рід == 'поверхня' and з in М_ЯКІ else 'додано: ' + рід
                п = підсумок.setdefault(група, [0, 0])
                п[0] += 1
                if сБ[0] + 1e-9 < сА[0]:
                    п[1] += 1
                    приклади.setdefault(група, []).append('%s см: %s → %s  +%s=%s → %s'
                                                           % (h, А or '∅', сА, рід, з, сБ))
for г in sorted(підсумок):
    print('| %s | пар %d | слабшає %d |' % (г, *підсумок[г]))
    for р in приклади.get(г, [])[:3]:
        print('    приклад:', р)
print('еталон дошки 16198: бруківка %s · бруківка + 20 хв %s'
      % (сила(9, dict(поверхня='бруківка')), сила(9, dict(поверхня='бруківка', дорога_пішки_хв=20))))
вс = sum(п[0] for г, п in підсумок.items() if '16200' not in г)
сл = sum(п[1] for г, п in підсумок.items() if '16200' not in г)
print('пар (без поверхонь < 1): %d · слабшає: %d' % (вс, сл))
