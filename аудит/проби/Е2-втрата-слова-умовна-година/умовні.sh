#!/bin/bash
# Мірило (2) доробки 16198: умовні тривалості, хвилини чи відстань без джерела на шляху суду ціни каблука K-SHO-16
# (перевірка_образу → аксесуари_суд → аксесуари_носіння.вартість_носіння; поломки — діагноз і злам руки 2;
# міст_відповіді — рядок ціни жінці). Шукає «<час> or|else <число>» і «<час> = <число>» поза коментарями; число —
# ненульове: нуль — це відсутній доданок чи «не довгий день», а не взята без джерела тривалість.
# Запуск з кореня дерева: bash аудит/проби/Е2-втрата-слова-умовна-година/умовні.sh
files="джерела/аксесуари_носіння.py джерела/аксесуари_суд.py джерела/перевірка_образу.py джерела/поломки.py джерела/міст_відповіді.py"
pat='^[^#]*(тривал|год|хв|пішки|дорог|відстан|хвилин)[^#]*\b(or|else)\s+([1-9][0-9]*(\.[0-9]+)?|0\.[0-9]*[1-9][0-9]*)\b|^[^#]*(тривал|год|хв|хвилин|відстан)[а-яіїє_]*\s*=\s*([1-9][0-9]*(\.[0-9]+)?|0\.[0-9]*[1-9][0-9]*)\s*[,)]'
grep -nE "$pat" $files
echo "місць: $(grep -cE "$pat" $files | awk -F: '{s+=$2} END {print s}')"
