#!/usr/bin/env python3
"""Крок 1 наряду «Перекладачка-ціна-вимір»: виклики перекладачки (мовний шар виходу) одного проходу на записах прогону
через справжній міст 20.11 (`аудит/проби/Живий-через-міст/`, 8 ситуацій × 2 проходи = 16 запитів жінки).

Перекладачка — промпти `мовний_шар.ПРОМПТ_ВИХОДУ` і його сестер: текст починається з «Ти — перекладачка» (три види:
«тексти» картки, «рядки» повідомлень коду, «репліка» стилістки в розмові). Перекладач її слів у коди («You are a
translator…», напрям «вхід») — окремим рядком довідки: у ціну $0,224 звіту 19.11 він не входив.

Джерела на кожен виклик:
- `стенд/службове/<с>/обміни.jsonl` — тіло, яке пішло в міст, відповідь Anthropic з `usage` (вхід, запис і читання
  кешу, вихід, `output_tokens_details.thinking_tokens`), секунди, прохід;
- `<с>/verdykty-*.json` — записи сторінки `мова_шару` (`напрям`, `де`, `коли`, `мс`, `вхід`): що перекладав виклик;
- `<с>/хід.md` — клік «Зібрати образи» і перша картка («Твої образи.»), як у `стенд/числа.py`.

Ціни — ті самі, що в `аудит/проби/модель-текст-claude/скрипти/рахунок.py`: Sonnet 5.5 $2 / $10 за млн, запис кешу $2,50,
читання $0,10. Повтор — `.retry` у `де` сторінки. Дубль — той самий текст входу (рядок «тексти») у двох і більше
викликах одного проходу.
Запуск з кореня репозиторію: python3 -I аудит/проби/перекладачка-ціна/вимір.py <тека виводу>
→ `виклики.tsv` (усі виклики), `прохід_с5_1.md` (таблиця одного проходу), підсумок markdown у stdout."""
import collections, datetime as D, glob, json, os, re, sys

ТЕКА = 'аудит/проби/Живий-через-міст'
ВИВІД = sys.argv[1]
ЦІНА = (2.0, 10.0, 2.5, 0.10)   # вхід, вихід, запис кешу, читання кешу — $ за млн токенів, Sonnet 5.5
ЗАПИТІВ = 16
ПРИКЛАД = ('с5_весілля_сестри', '1')


def час(т):
    return D.datetime.fromisoformat(т.replace('Z', '+00:00')).timestamp()


def вид(т):
    if т.startswith('Ти — перекладачка'):
        п = т[40:140]
        return 'репліка' if 'репліку' in п else 'рядки' if 'рядки' in п else 'тексти' if 'тексти' in п else '?'
    if т[:200].find('You are a translator') >= 0:
        return 'вхід'
    return None


def записи_сторінки(с):
    """усі записи `мова_шару` з verdykty ситуації, без повторів (той самий запис стоїть у кількох вердиктах)"""
    вих, бачено = [], set()

    def обхід(о):
        if isinstance(о, dict):
            for к, з in о.items():
                if к == 'мова_шару' and isinstance(з, list):
                    for р in з:
                        if isinstance(р, dict) and р.get('коли'):
                            кл = (р.get('коли'), р.get('де'), р.get('напрям'))
                            if кл not in бачено:
                                бачено.add(кл); вих.append(р)
                else:
                    обхід(з)
        elif isinstance(о, list):
            for з in о:
                обхід(з)
    for ф in glob.glob(os.path.join(ТЕКА, с, 'verdykty-*.json')):
        обхід(json.load(open(ф, encoding='utf-8')))
    return вих


def шматки(в):
    """рядки входу запису сторінки — щоб знайти їх у тексті промпта"""
    if isinstance(в, str):
        return [в]
    if isinstance(в, dict):
        return [ш for з in в.values() for ш in шматки(з)]
    if isinstance(в, list):
        return [ш for з in в for ш in шматки(з)]
    return []


def знайти_запис(виклик, записи, промпт):
    """запис сторінки, у вікні якого почався виклик і чий вхід стоїть у промпті"""
    т0 = виклик['т0']
    кандидати = [р for р in записи if час(р['коли']) - 0.05 <= т0 <= час(р['коли']) + (р.get('мс') or 0) / 1000 + 0.05]
    def влучань(р):
        return sum(1 for ш in шматки(р.get('вхід')) if len(ш) >= 12 and json.dumps(ш, ensure_ascii=False)[1:-1][:60] in промпт)
    кандидати.sort(key=lambda р: (-влучань(р), час(р['коли'])))
    return кандидати[0] if кандидати and (влучань(кандидати[0]) or len(кандидати) == 1) else None


def тексти_входу(промпт):
    """тексти, які виклик «тексти» дав перекласти: JSON після «ТЕКСТИ:»"""
    м = re.search(r'\nТЕКСТИ:\n(\{.*\})\s*$', промпт, re.S)
    if not м:
        return {}
    try:
        return {к: (з if isinstance(з, str) else json.dumps(з, ensure_ascii=False)) for к, з in json.loads(м.group(1)).items()}
    except Exception:
        return {}


def картки(с):
    """прохід → (клік «Зібрати образи», поява першої картки), секунди епохи"""
    т = open(os.path.join(ТЕКА, с, 'хід.md'), encoding='utf-8').read()
    кроки = [(int(м[1]), час(м[2]), м[3], м[4]) for м in
             re.finditer(r'### (\d+) · (\S+) · прохід (\d) · [^\n]*\n(.*?)(?=\n### |\Z)', т, re.S)]
    вих = {}
    for п in sorted({к[2] for к in кроки}):
        К = [к for к in кроки if к[2] == п]
        клік = [к for к in К if 'Зібрати образи»' in к[3] and 'дія скрипта' in к[3]]
        if клік:
            перша = [к for к in К if к[0] > клік[0][0] and 'Твої образи.' in к[3]]
            вих[п] = (клік[0][1], перша[0][1] if перша else None)
    return вих


виклики = []
for тека in sorted(glob.glob(os.path.join(ТЕКА, 'стенд', 'службове', 'с*'))):
    с = os.path.basename(тека)
    записи = записи_сторінки(с)
    кк = картки(с)
    for л in open(os.path.join(тека, 'обміни.jsonl'), encoding='utf-8'):
        x = json.loads(л)
        тіло = json.loads(x['запит'])
        зміст = тіло['messages'][0]['content']
        промпт = зміст[0]['text'] if isinstance(зміст, list) else зміст
        в = вид(промпт)
        if not в:
            continue
        try:
            відп = json.loads(x['відповідь']); u = відп['usage']
        except Exception:
            відп, u = None, None
        в0 = {'ситуація': с, 'прохід': str(x['прохід']), 'т0': час(x['час']), 'с': float(x['с']), 'вид': в,
              'статус': x.get('статус'), 'знаків_промпта': len(промпт), 'модель': тіло.get('model')}
        if u:
            в0.update(вхід=u.get('input_tokens', 0), запис=u.get('cache_creation_input_tokens', 0) or 0,
                      читання=u.get('cache_read_input_tokens', 0) or 0, вихід=u.get('output_tokens', 0),
                      думки=(u.get('output_tokens_details') or {}).get('thinking_tokens', 0) or 0)
            в0['usd'] = (в0['вхід'] * ЦІНА[0] + в0['вихід'] * ЦІНА[1] + в0['запис'] * ЦІНА[2] + в0['читання'] * ЦІНА[3]) / 1e6
            в0['відповідь'] = ''.join(б.get('text', '') for б in відп.get('content', []) if б.get('type') == 'text')
        р = знайти_запис(в0, записи, промпт)
        в0['де'] = (р.get('напрям', '') + ':' + р.get('де', '')) if р else '—'
        тт = тексти_входу(промпт) if в == 'тексти' else {}
        в0['текстів'] = len(тт) if тт else (len(р.get('вхід') or {}) if р else 0)
        в0['знаків_текстів'] = sum(len(з) for з in тт.values()) if тт else 0
        в0['тексти'] = тт
        клік, перша = кк.get(в0['прохід'], (None, None))
        в0['до_картки'] = bool(клік and перша and в0['т0'] >= клік and в0['т0'] + в0['с'] <= перша)
        в0['від_кліку'] = round(в0['т0'] - клік, 1) if клік else None
        в0['перша_картка'] = round(перша - клік, 1) if клік and перша else None
        виклики.append(в0)

# дублі: той самий текст входу «тексти» у двох і більше викликах одного проходу
за_проходом = collections.defaultdict(list)
for в in виклики:
    за_проходом[(в['ситуація'], в['прохід'])].append(в)
дублів_текстів = дублів_знаків = 0
for зз in за_проходом.values():
    лік = collections.Counter(т for в in зз if в['вид'] == 'тексти' and '.retry' not in в['де'] for т in set(в['тексти'].values()))
    for т, н in лік.items():
        if н > 1:
            дублів_текстів += н - 1; дублів_знаків += (н - 1) * len(т)

os.makedirs(ВИВІД, exist_ok=True)
ПОЛЯ = ['ситуація', 'прохід', 'від_кліку', 'вид', 'де', 'текстів', 'знаків_текстів', 'знаків_промпта', 'вхід', 'запис',
        'читання', 'вихід', 'думки', 'с', 'до_картки', 'перша_картка', 'usd', 'статус']
with open(os.path.join(ВИВІД, 'виклики.tsv'), 'w', encoding='utf-8') as ф:
    ф.write('\t'.join(ПОЛЯ) + '\n')
    for в in sorted(виклики, key=lambda в: (в['ситуація'], в['прохід'], в['т0'])):
        ф.write('\t'.join(str(round(в.get(п), 5) if isinstance(в.get(п), float) else в.get(п, '')) for п in ПОЛЯ) + '\n')

# таблиця одного проходу
with open(os.path.join(ВИВІД, 'прохід_с5_1.md'), 'w', encoding='utf-8') as ф:
    зз = sorted(за_проходом[ПРИКЛАД], key=lambda в: в['т0'])
    ф.write(f'Виклики перекладачки й перекладача входу, {ПРИКЛАД[0]}, прохід {ПРИКЛАД[1]} (міст 20.11, Sonnet 5.5). '
            f'Перша картка — через {зз[0]["перша_картка"]} с після кліку «Зібрати образи».\n\n')
    ф.write('| с від кліку | вид | що перекладає (`де` сторінки) | текстів | знаків текстів | знаків промпта | токенів входу | '
            'вихід: думки / текст | с | до першої картки | $ |\n|---|---|---|---|---|---|---|---|---|---|---|\n')
    for в in зз:
        ф.write(f"| {в['від_кліку']} | {в['вид']} | {в['де']} | {в['текстів']} | {в['знаків_текстів'] or '—'} | "
                f"{в['знаків_промпта']} | {в['вхід'] + в['запис'] + в['читання']} | {в['думки']} / {в['вихід'] - в['думки']} | "
                f"{в['с']:.1f} | {'так' if в['до_картки'] else 'ні'} | {в['usd']:.4f} |\n")

# підсумок на запит жінки
def сума(фільтр):
    зз = [в for в in виклики if фільтр(в) and 'usd' in в]
    с = collections.Counter()
    for в in зз:
        for п in ('вхід', 'запис', 'читання', 'вихід', 'думки', 'usd', 'с', 'знаків_промпта'):
            с[п] += в[п]
        с['n'] += 1
        с['usd_вхід'] += (в['вхід'] * ЦІНА[0] + в['запис'] * ЦІНА[2] + в['читання'] * ЦІНА[3]) / 1e6
        с['usd_вихід'] += в['вихід'] * ЦІНА[1] / 1e6
        с['до_картки'] += в['до_картки']
        с['повторів'] += '.retry' in в['де']
    return с

print('| клас | викликів на запит | токенів входу | вихід: думки / текст | $ на запит | з них вхід / вихід | с на виклик p50 | до першої картки, викликів на запит |')
print('|---|---|---|---|---|---|---|---|')
РЯДИ = [('перекладачка — тексти', lambda в: в['вид'] == 'тексти'), ('перекладачка — рядки', lambda в: в['вид'] == 'рядки'),
        ('перекладачка — репліка', lambda в: в['вид'] == 'репліка'),
        ('**перекладачка разом**', lambda в: в['вид'] in ('тексти', 'рядки', 'репліка')),
        ('довідка: перекладач входу', lambda в: в['вид'] == 'вхід')]
підсумок = {}
for назва, ф in РЯДИ:
    с = сума(ф)
    сек = sorted(в['с'] for в in виклики if ф(в))
    підсумок[назва] = dict(с)
    print(f"| {назва} | {с['n'] / ЗАПИТІВ:.2f} | {(с['вхід'] + с['запис'] + с['читання']) / ЗАПИТІВ:,.0f} | "
          f"{с['думки'] / ЗАПИТІВ:,.0f} / {(с['вихід'] - с['думки']) / ЗАПИТІВ:,.0f} | {с['usd'] / ЗАПИТІВ:.3f} | "
          f"{с['usd_вхід'] / ЗАПИТІВ:.3f} / {с['usd_вихід'] / ЗАПИТІВ:.3f} | {сек[len(сек) // 2]:.1f} | {с['до_картки'] / ЗАПИТІВ:.2f} |")
пер = [в for в in виклики if в['вид'] in ('тексти', 'рядки', 'репліка')]
print(f"\nповторів (`.retry`): {sum('.retry' in в['де'] for в in пер)} з {len(пер)} викликів; без запису сторінки: "
      f"{sum(в['де'] == '—' for в in пер)}; не-200: {sum(str(в['статус']) != '200' for в in пер)}; моделі: "
      f"{dict(collections.Counter(в['модель'] for в in пер))}")
print(f"дублі текстів входу «тексти» в межах проходу (без повторів): {дублів_текстів} текстів, {дублів_знаків} знаків")
пк = collections.Counter(в['де'].split(':')[-1].split('.')[0] for в in пер)
print('що перекладають (де сторінки, без суфіксів):', dict(пк.most_common()))
json.dump(підсумок, open(os.path.join(ВИВІД, 'підсумок.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
