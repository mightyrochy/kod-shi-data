"""Дошка 15107 (вада 23): рядок випадку називає місце двічі. Паспорти — з записаних відповідей мовної моделі першого
живого прогону (`аудит/проби/живий-як-людина-1/стенд/службове/<с>/обміни.jsonl.gz`, відповіді з `update`), рядок шматків
— `паспорт_шматками_людині`. Два варіанти кожного: як записано і «без ключа нагоди» (так на екрані стояла подія
реченням; у запису ключ нагоди є, тож дубль відтворено прибраним `occasion`). Запуск: python3 -W ignore аудит/проби/Екран-наново-15107/рядок_місця.py"""
import glob, gzip, json, os, sys
К = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
sys.path.insert(0, К + "/джерела"); os.chdir(К + "/джерела")
import мовний_шар as МШ, паспорт_нагоди as ПН
ф_ = lambda ш: " · ".join(x["текст"] for x in ш)
for ф in sorted(glob.glob(К + "/аудит/проби/живий-як-людина-1/стенд/службове/*/обміни.jsonl.gz")):
    с = ф.split("/")[-2]
    for н, р in enumerate(gzip.open(ф, "rt", encoding="utf-8")):
        d = json.loads(р)
        try:
            т = json.loads(d["відповідь"])["content"][0]["text"]; в = json.loads(т)
        except (ValueError, KeyError, IndexError):
            continue
        if not isinstance(в, dict) or "event" not in (в.get("update") or {}):
            continue
        слова = [x for ч in в.get("text") or [] for x in ч.get("her_words") or []] + [в["update"]["event"]]
        for мітка, вв in (("як записано", в), ("без нагоди", dict(в, update={k: x for k, x in в["update"].items() if k != "occasion"}))):
            пр = МШ.прийняти_розмову(json.dumps(вв, ensure_ascii=False))
            п = МШ.паспорт_з_шару(пр["внутрішня"], {}, None, None, слова_ходу=слова, частини=пр.get("частини"))["паспорт"]
            print("%s #%d %-12s | %s" % (с[:2], н, мітка, ф_(ПН.паспорт_шматками_людині(п))))
# рядок живого прогону (вада 23): місце слів моделі — «ресторані», подія називає його ж
п = {"подія": "побачення в ресторані", "місце": "ресторан_районний", "місце_слова": "ресторані", "пора": "вечір"}
print("с4 живий рядок       | %s" % ф_(ПН.паспорт_шматками_людині(п)))
# 15232: місце — частина іншого слова події, не те саме місце; 15233: знак місця (ключ шматка) не зникає
for п in ({"подія": "зустріч кафедри", "місце": "кафе", "місце_слова": "кафе", "пора": "вечір"},
          {"подія": "побачення в ресторані", "місце": "ресторан_районний", "місце_слова": "ресторані", "пора": "вечір"}):
    print("ключі: %s | %s" % (" ".join(x["ключ"] for x in ПН.паспорт_шматками_людині(п)), ф_(ПН.паспорт_шматками_людині(п))))
