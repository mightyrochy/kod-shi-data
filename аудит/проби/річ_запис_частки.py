"""Порахувати частки чужих полів за вибіркою п.3 (Річ-запис-речі): із блоки.json й очі_п3.json.

Запуск із кореня: python3 -X utf8 аудит/проби/річ_запис_частки.py [ТЕКА] — без мережі, вивід детермінований.
Вердикт поля: рішення очима з очі_п3.json, інакше ознака чужого тексту в самому записі (мітки вкладок
інтерфейсу, список інших товарів, SEO-мета, хвіст заголовка вкладки), інакше машинний вердикт блоків.
«чужий» — текст не з блоку цього товару; «нема» — на сторінці немає, але чужим не доведено (інша
мовна версія, змінений сайт); «порожнє» й «виключено» у знаменник не входять. Розділ — окремо: він
береться з таксономії крамниці, не з блоку сторінки, тому рахується збіг із крихтами, а не чужість.
"""
import collections
import json
from pathlib import Path
import sys

ТЕКА = Path(__file__).resolve().parents[2] / 'аудит/проби/річ_запис_каталог_2026_10_30'
ПОЛЯ = ['назва', 'опис', 'склад']


def main():
    """Звести вердикти й записати частки.json."""
    тека = Path(sys.argv[1]) if len(sys.argv) > 1 else ТЕКА
    блоки = json.loads((тека / 'блоки.json').read_text(encoding='utf-8'))
    очі = {(о['id'], о['поле']): о for о in json.loads((тека / 'очі_п3.json').read_text(encoding='utf-8'))}
    підсумок = {поле: collections.Counter() for поле in ПОЛЯ + ['розділ']}
    за_крамницею = collections.defaultdict(lambda: {поле: collections.Counter() for поле in ПОЛЯ + ['розділ']})
    чужі = []
    for р in блоки:
        for поле in ПОЛЯ + ['розділ']:
            вид = None
            if (р['id'], поле) in очі:
                вердикт, вид = очі[(р['id'], поле)]['вердикт'], очі[(р['id'], поле)]['вид']
            elif поле != 'розділ' and р.get(поле + '_ознаки'):
                вердикт, вид = 'чужий', '+'.join(р[поле + '_ознаки'])
            else:
                вердикт = р[поле]['вердикт']
            підсумок[поле][вердикт] += 1
            за_крамницею[р['крамниця']][поле][вердикт] += 1
            if вердикт == 'чужий':
                чужі.append(dict(id=р['id'], поле=поле, вид=вид, url=р['url']))
    вивід = dict(сторінок=len(блоки), крамниць=len({р['крамниця'] for р in блоки}),
        поля={п: dict(підсумок[п]) for п in підсумок}, чужі=чужі,
        за_крамницею={к: {п: dict(в[п]) for п in в} for к, в in sorted(за_крамницею.items())})
    (тека / 'частки.json').write_text(json.dumps(вивід, ensure_ascii=False, sort_keys=True, indent=1) + '\n', encoding='utf-8')
    for п in ПОЛЯ + ['розділ']:
        в = підсумок[п]
        знаменник = sum(в[к] for к in в if к not in ('порожнє', 'виключено'))
        print(f'{п}: {dict(в)}; чужих {в["чужий"]} з {знаменник} непорожніх = {100 * в["чужий"] / (знаменник or 1):.1f} %')
    крамниці_з_чужим = sorted(к for к, в in за_крамницею.items() if any(в[п]['чужий'] for п in ПОЛЯ))
    print('крамниць із чужим полем:', len(крамниці_з_чужим), крамниці_з_чужим)
    print('сторінок із чужим принаймні в одному полі:', len({ч['id'] for ч in чужі}))


if __name__ == '__main__':
    main()
