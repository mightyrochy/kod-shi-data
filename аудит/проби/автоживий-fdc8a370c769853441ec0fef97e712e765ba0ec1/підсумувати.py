"""Пише звіт тільки за завершеними записами всього призначеного плану."""
from collections import Counter
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import re
import subprocess
from urllib.parse import quote

ТЕКА = Path(__file__).resolve().parent
КОРІНЬ = ТЕКА.parents[2]
SHA = "6530d4324c6aee95d5e0d4a55cfd154c4c2a8e9a"

def main():
    дані = json.loads((ТЕКА / "ФАКТИ.json").read_text(encoding="utf-8"))
    середовище = json.loads((ТЕКА / "середовище.json").read_text(encoding="utf-8"))
    план = json.loads((ТЕКА / "НАРЯД.md").read_text(encoding="utf-8").split("ПЛАН ЖИВОГО — ДАНІ (JSON):\n", 1)[1].splitlines()[0])
    if set(дані) != set(план["scenes"]):
        raise RuntimeError("Зведення не відповідає плану")
    for сцена, д in дані.items():
        if (д.get("результат") or {}).get("rc") not in (0, 1):
            raise RuntimeError("Незавершений запис: " + сцена)
        if not (д.get("доказ") or {}).get("вердикт", {}).get("доведено"):
            raise RuntimeError("Неповний доказ: " + сцена)
        if д["результат"].get("sha") != середовище["штамп"]:
            raise RuntimeError("Інший штамп збірки: " + сцена)
    завершені = re.findall(r"^\S+ (\S+) rc=\d+$", (ТЕКА / "done.txt").read_text(encoding="utf-8"), re.M)
    if Counter(завершені) != Counter({с: 1 for с in план["scenes"]}):
        raise RuntimeError("У done.txt не рівно один завершений запуск кожної сцени")
    база = (ТЕКА / "НОВА_БАЗА.md").read_text(encoding="utf-8")
    rc_бази = (ТЕКА / "нова_база_rc.txt").read_text(encoding="utf-8").strip()
    main_бази = (ТЕКА / "нова_база_main.txt").read_text(encoding="utf-8").strip()
    відповіді = (ТЕКА / "ВІДПОВІДІ.md").read_text(encoding="utf-8")
    if "ПІСЛЯ ЗАПИСУ" in відповіді:
        raise RuntimeError("Не завершено відповіді на всі питання")
    зелених = sum(д["зелених_звірок"] for д in дані.values())
    червоних = sum(д["червоних_звірок"] for д in дані.values())
    png = sum(д["знімків_png"] for д in дані.values())
    коди = Counter(д["результат"]["rc"] for д in дані.values())
    початок = min(д["результат"]["початок"] for д in дані.values())
    кінець = max(д["результат"]["кінець"] for д in дані.values())
    рядки = ["# Автоматичний тестовий прогін " + ТЕКА.name, "",
        f"Виконано {len(дані)} із {len(план['scenes'])} сцен рівно по одному разу: rc=0 — {коди[0]}, rc=1 — {коди[1]}; доказ доведено в усіх записах. Збережено {png} PNG, {зелених} зелених і {червоних} червоних звірок стенда.", "",
        "Це тестові сцени з реєстру, за визначенням `живі_порядок.md`. Оцінки живої людини немає; дотики й вердикти стенда автоматичні. Зелені звірки не означають, що всі питання PR пройшли; залишки й невиміряні умови наведено нижче.", "",
        f"Початок записів: {початок}; кінець: {кінець}. Час UTC.", "",
        f"Призначений коміт збірки: `{SHA}`. Штамп коду: `{середовище['штамп']}`. Перевірка предка перед прогоном: rc={середовище['перевірка_предка_rc']}; origin/main тоді — `{середовище['origin_main']}`.", "",
        "Зібрану сторінку взято з окремого тимчасового дерева призначеного SHA. Стенд, його місцеві проби, проксі й модуль доказу між ним і початковою головою гілки не змінювалися. Реалізацію продукту, правила та обгортку не правили.", "",
        "Моделі: Qwen `qwen/qwen3.5-9b`, контекст 57344; MamayLM `mamaylm-gemma-3-12b-it-v2.0`, контекст 16384; parallel=1, ODNOCHASNO=1, почерговий HTTP-проксі. Реальні конфігурації підтверджені в `проксі.txt` кожної сцени. NODE_OPTIONS і PYTHONPATH обгортки збережені. Перед першою сценою завантажених екземплярів не було.", "",
        "## Записи", "",
        "| Сцена | Режим | rc | Зелені / червоні | Секунд | PNG |",
        "|---|---|---:|---:|---:|---:|"]
    for сцена, д in дані.items():
        режим = д["доказ"]["режим"]["сцена"]["режим"]
        рядки.append(f"| [{сцена}]({сцена}/лог.txt) | {режим} | {д['результат']['rc']} | {д['зелених_звірок']} / {д['червоних_звірок']} | {д['результат']['секунд']} | {д['знімків_png']} |")
    рядки.extend(["", "Повні вхідні змінні, команди й коди виходу — `команди.jsonl`, `done.txt`, `запускач.txt`, `результат.json` кожної сцени. Відповіді та запити моделі — `VIDPOVIDI/обмін/`; повтор — `повтор.json`; файл для читання як від тестувальниці — `вердикти.txt` повних сцен; знімки — `знімки/`. Короткі сцени розмови мають паспортні виміри й картку в `лог.txt`, без вигаданого файлу вердиктів.", "", "## Відповіді на питання PR", "", відповіді.strip(), "", "## Червоні звірки", ""])
    групи = Counter(р.split("  →  ", 1)[0] for д in дані.values() for р in д["червоні"])
    for назва, n in групи.items():
        рядки.append(f"- {n} × {назва.lstrip('✗ ')}")
    рядки.extend(["", "Дослівні червоні рядки з даними — `ЧЕРВОНІ.txt`; це перелік звірок, не число незалежних вад. FOTO=0 прямо позначає, що фото не вимірювалися; такі червоні не є виміром доставки. Словесна звірка Л-4 використовує корені слів, тому сама по собі не доводить сторонній id речі.", "", "## ДО → ПІСЛЯ", "",
        "ДО — джерела, названі в дослівному наряді; історичний результат зимової сцени знайдено `живі_до.py` і збережено в `ДО.txt`. Його код 8af69a14272638dd52a938e9da6c08b8acf8a77d, між ним і названою базою 2777 комітів та 615 змінених файлів джерел: він не доводить причину відмінності. Нових модельних ДО не запускали.", "",
        f"ПІСЛЯ — {len(дані)} завершених записів призначеної збірки; числа вище є фактами цього прогону. Коренів і рядків дошки не закрито. Нових номерів цей наряд не видає.", "", "## Нова база", "",
        f"Команда: `node аудит/проби/нова_база.js аудит/проби/{ТЕКА.name}`. Код виходу: {rc_бази}. origin/main на час формування — `{main_бази}`. Повний вивід — `нова_база_вивід.txt`.", "", *база.splitlines()[2:], "",
        "Базу руками не писали й не правили. Записи без бази лишаються доказами.", "", "## Завершення", "",
        "Факти додано до 8 наявних рядків дошки зі збереженням станів. `python джерела/прилади/згорнути_дошку.py --лише-перевірити`: rc=0, помилок 0; вивід у `перевірка_дошки.txt`.", "",
        "Власні екземпляри й проксі прибирав записувач після кожної сцени; відповіді REST збережені в результатах. Остаточний стан ресурсів — `очищення.json`. Гілку публікує й PR відкриває обгортка; шаблон наряду залишено.", "",
        "ПЕРЕВІРЕНО ЗБІРКУ: " + SHA, ""])
    текст = "\n".join(рядки)
    (ТЕКА / "ЗВІТ.md").write_text(текст, encoding="utf-8")
    head = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=КОРІНЬ, text=True, encoding="utf-8").strip()
    url = "https://github.com/mightyrochy/kod-shi-data/tree/" + head + "/" + quote(str(ТЕКА.relative_to(КОРІНЬ)).replace("\\", "/"), safe="/")
    коміт = f"Автоживий: {len(дані)} тестових сцен збірки fdc8a370 та невиміряні умови\n\n"
    коміт += f"Що змінено: додано {len(дані)} записів, знімки, відповіді на питання й факти наявних симптомів дошки.\n"
    коміт += "Перевірено: зібрана сторінка у справжньому Chromium із двома локальними моделями; повний доказ кожної сцени. Продукт і правила не змінювалися.\n\n"
    коміт += текст + "\n[Докази записів](" + url + ")\n"
    (ТЕКА / "КОМІТ.txt").write_text(коміт, encoding="utf-8")
    print(f"Звіт: {len(дані)} сцен, {png} PNG, {зелених} зелених, {червоних} червоних; rc бази {rc_бази}")

if __name__ == "__main__":
    main()
