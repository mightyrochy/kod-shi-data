# -*- coding: utf-8 -*-
"""Е3-одна-величина ч37, крок 2: повтор частки маски речі на кадрах її галереї й розбіг «клас слота проти пікселя».
Сукупність — усі записи `джерела/каталог_кадри.json.gz` (знято 2026-11-08 на ноутбуці, `жнива_маски.маска_речі`
ATR → SAM): кадр несе лише `частка_маски` — пікселі маски речі проти поля КАДРУ, а не проти поля образу. Слот речі —
з пакета каталогу мосту (`--кеш`, той самий, що в `Е3_ч33_частка.py`; нема — збирає з `каталог_повний.xml`).
    python3 аудит/проби/Е3_ч37_похибка_частки/кадри.py --кеш /tmp/кеш.pkl
Друкує: (а1) те саме фото двічі (jpg і webp одного файла галереї) — повтор маски на тих самих пікселях; (а2) кадри
одного класу (`клас` аркуша) однієї речі — розмах і SD частки; приклади — вибірка із зерном 37; (б) речі слотів класу
(`outfit.клас_площі`): частка кадру проти частки класу образу — чи є в даних поле образу, без якого розбіг не лічиться."""
import sys, pathlib, os, io, contextlib, json, gzip, random, pickle, collections, statistics as S
КОРІНЬ = pathlib.Path(__file__).resolve().parents[3]
арг = lambda і, т=None: sys.argv[sys.argv.index(і) + 1] if і in sys.argv else т
код = КОРІНЬ / "джерела"; кеш = арг("--кеш")
os.chdir(код); sys.path.insert(0, str(код))
import outfit as O
мета, записи = (lambda д: (д["мета"], д["записи"]))(json.load(gzip.open(код / "каталог_кадри.json.gz")))
if not (кеш and pathlib.Path(кеш).exists()):
    import feed as Ф, bridge as B
    вх = json.load(open(код / "стенд_вх.json", encoding="utf-8")); вх.update(гілка=0)
    вх["каталог"] = Ф.каталог_на_диску(str(код / "каталог_повний.xml"))
    with contextlib.redirect_stdout(io.StringIO()): B.виклик("запити", json.dumps(вх, ensure_ascii=False))
    кеш and pickle.dump(B.каталог_останнього_пакета(), open(кеш, "wb"))
кат = pickle.load(open(кеш, "rb")) if кеш else B.каталог_останнього_пакета()
слот = {c["id"]: c.get("слот") for c in кат}
кв = lambda р, *пп: "—" if not р else " ".join("p%d %.3f" % (п * 100, sorted(р)[round(п * (len(р) - 1))]) for п in пп)
міряні = lambda v: [f for f in v if isinstance(f.get("частка_маски"), (int, float))]
print("джерело: каталог_кадри.json.gz, знято %s, маска %s; записів %d (мета: %s), з кадром із часткою маски %d; кадрів із часткою %d"
      % (мета["знято"], мета["маска"], len(записи), мета.get("записів"), sum(1 for v in записи.values() if міряні(v)),
         sum(len(міряні(v)) for v in записи.values())))
# (а1) те саме фото: каталог галереї (тека-хеш) і стем файла збігаються, різниться лише кодування (jpg / webp)
пари, клас_різний = [], 0
for k, v in записи.items():
    гр = collections.defaultdict(list)
    for f in міряні(v):
        ш = pathlib.PurePosixPath(f["файл"].lower()); гр[(ш.parent.name, ш.stem)].append(f)
    for fs in гр.values():
        if len(fs) >= 2:
            пари.append(max(f["частка_маски"] for f in fs) - min(f["частка_маски"] for f in fs))
            клас_різний += len({f.get("клас") for f in fs}) > 1
print("(а1) те саме фото двічі (jpg і webp): груп %d; |Δ частки| %s; Δ = 0: %d; клас аркуша різний на тому самому фото: %d"
      % (len(пари), кв(пари, .5, .9, 1.0), sum(1 for р in пари if р == 0), клас_різний))
# (а2) кадри одного класу однієї речі
приклади = []
for клас in ("на_моделі", "ціла_річ", "деталь", None):
    розм, сд, речей = [], [], 0
    for k, v in записи.items():
        s = [f["частка_маски"] for f in міряні(v) if f.get("клас") == клас]
        if len(s) >= 2:
            речей += 1; розм.append(max(s) - min(s)); сд.append(S.stdev(s))
            приклади.append((клас, k, слот.get(k), sorted(s)))
    print("(а2) клас %-9s речей з 2+ кадрами %4d · розмах %s · SD %s"
          % (клас or "без класу", речей, кв(розм, .1, .5, .9, 1.0), кв(сд, .5, .9)))
for п in random.Random(37).sample(приклади, 8):
    print("     зерно 37: %-9s %-28s %-8s частки %s" % (п[0] or "—", п[1][:28], п[2], [round(x, 3) for x in п[3]]))
# (б) клас слота проти пікселя
клас_р = collections.defaultdict(list)
for k, v in записи.items():
    кл = O.клас_площі(слот.get(k))
    if кл:
        клас_р[(кл, слот.get(k))] += [f["частка_маски"] for f in міряні(v)]
for (кл, сл), s in sorted(клас_р.items()):
    print("(б) %-9s %-14s частка класу образу %.2f · кадрів %4d · частка КАДРУ %s · ≥ 0.03 кадру: %d"
          % (кл, сл, O.ЧАСТКА_КЛАСУ[кл], len(s), кв(s, .1, .5, .9), sum(1 for x in s if x >= 0.03)))
поля = collections.Counter(к for v in записи.values() for f in v for к in f)
print("(б) поля кадру: %s — поля образу (пікселі решти речей, тіла, шкіри) нема: частку речі в ОБРАЗІ з кадру не "
      "отримати, розбіг із класом слота (частка образу) не лічиться" % ", ".join(sorted(поля)))
