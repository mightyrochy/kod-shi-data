"""Зіставити кожну записану знахідку трьох модулів на батареї ДО й ПІСЛЯ."""
import collections
import gzip
import json
import sys

ПОЛЯ = ('правило', 'сила', 'регістр', 'блокує', 'суть', 'речі', 'полярність', 'учасники', 'заяви')


def читати(шлях):
    """Прочитати результати й згрупувати ваги за незмінними полями знахідки та входом перевірки."""
    with gzip.open(шлях, 'rt', encoding='utf-8') as ф:
        дані = json.load(ф)
    групи = collections.defaultdict(list)
    for перевірка, модуль, з in дані['записи']:
        ключ = json.dumps([перевірка, модуль, {п: з.get(п) for п in ПОЛЯ}],
                          ensure_ascii=False, sort_keys=True)
        групи[ключ].append(з['сила_нп'])
    return дані, групи


def main():
    """Перевірити склад, категорії, блокування й результати; надрукувати точні переходи ваг."""
    (до, групи_до), (після, групи_після) = map(читати, sys.argv[1:3])
    склад_до = collections.Counter({к: len(v) for к, v in групи_до.items()})
    склад_після = collections.Counter({к: len(v) for к, v in групи_після.items()})
    print('Знахідок:', len(до['записи']), '→', len(після['записи']))
    print('Доданих:', sum((склад_після - склад_до).values()),
          'знятих:', sum((склад_до - склад_після).values()))
    assert склад_до == склад_після, 'склад, категорія, регістр або блокування змінились'
    assert до['результати'] == після['результати'], 'коди виходу перевірок відрізняються'
    переходи = collections.Counter()
    за_правилом = collections.Counter()
    for ключ, ваги in групи_до.items():
        правило = json.loads(ключ)[2]['правило']
        за_правилом[правило] += len(ваги)
        for було, стало in zip(sorted(ваги), sorted(групи_після[ключ])):
            if було != стало:
                переходи[правило, було, стало] += 1
    print('Змін ваги:', sum(переходи.values()))
    print('\n| Правило | ДО | ПІСЛЯ | Кількість |\n|---|---|---|---|')
    for (правило, було, стало), к in sorted(переходи.items(), key=str):
        print(f'| {правило} | {було} | {стало} | {к} |')
    print('\nЗнахідок за правилом:', dict(sorted(за_правилом.items())))
    print('Провали ДО = ПІСЛЯ:', [р for р in до['результати'] if р[1]])
    assert {п[0] for п in переходи} <= {'K-EDG-01', 'K-ACC-01', 'K-PRC-01'}


if __name__ == '__main__':
    main()
