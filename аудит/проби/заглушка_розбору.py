# -*- coding: utf-8 -*-
"""заглушка_розбору.py — ФАЙЛ РОЗБОРУ КАТАЛОГУ ТІЄЇ САМОЇ ФОРМИ, БЕЗ МОДЕЛІ (наряд К-3).

ЧОМУ ЦЕ Є. Короткий запис речі (`каталог_коди`, `дріт_моделі.річ(короткий=True)`) живий лише
тоді, коли поруч лежить файл розбору каталогу — а справжній зробить ноутбук
(`каталог_розбір_прогін.py` на MamayLM/Lapa, рішення власника 27.09). Щоб ФОРМУ й ЛІЧБУ можна
було перевірити в хмарі вже сьогодні, цей скрипт кладе файл тієї самої форми з ДВОХ джерел:
  · коди — зі СПРАВЖНІХ відповідей живого прогону Н-1 26.09 (`аудит/тести/сирі_2026-09-26/
    p3_katalog_rozbir.tar.gz`) через `каталог_розбір.з_відповіді`: 60 речей, 60 з 60 валідних.
    Речі каталогу дістають їх по колу, стало (`sha1(id)`), бо вимір тут — про РОЗМІР і форму
    запису, не про правильність кодів на конкретній речі;
  · рядок особливостей — ВИГАДАНИЙ і позначений як вигаданий: перше слово «stub», решта —
    коди тієї самої речі англійськими словами (тип, крій, тканина, оздоба, колір). Так рядок
    англійський, без жодного українського слова крамниці, і довжиною близький до справжнього
    (приклад власника «cropped boxy cardigan, chunky cable knit, pearl buttons, cappuccino
    shade» — 73 символи; стеля тут `СТЕЛЯ_ОСОБЛИВОСТЕЙ`). Скільки він важить — друкує проба.

ЧОГО ЦЕЙ ФАЙЛ НЕ Є. Не вимір якості розбору (його робить ноутбук очима власника на фото) і не
дані продукту: він лягає в теку, яку скаже `--куди`, і продукт бере його лише через
`ROZBIR_KODY`. У `джерела/` його класти не треба — там місце справжнього файла.

ПРОГІН:  python3 аудит/проби/заглушка_розбору.py [--куди <файл.json.gz>] [--скільки N]
"""
import argparse
import glob
import gzip
import hashlib
import io
import json
import os
import sys
import tarfile
import tempfile

ТУТ = os.path.dirname(os.path.abspath(__file__))
КОРІНЬ = os.path.dirname(os.path.dirname(ТУТ))
ДЖЕРЕЛА = os.path.join(КОРІНЬ, "джерела")
if ДЖЕРЕЛА not in sys.path:
    sys.path.insert(0, ДЖЕРЕЛА)

import каталог_коди as КК              # noqa: E402
import каталог_розбір as КР            # noqa: E402
import фід_каталог as ФК               # noqa: E402
import фід_розбір as ФР                # noqa: E402

СИРІ = os.path.join(КОРІНЬ, "аудит", "тести", "сирі_2026-09-26", "p3_katalog_rozbir.tar.gz")
МОДЕЛЬ_СИРИХ = "mamaylm"               # тека прогону в архіві; Lapa лежить поруч
СТЕЛЯ_ОСОБЛИВОСТЕЙ = 85                # символів: приклад власника 73, стеля наряду — 15 слів
# ── ЩО САМЕ ВИГАДУЄ ЗАГЛУШКА: ТЕ, ЧОГО КОДИ НЕ НЕСУТЬ ──────────────────────
# Правило рядка особливостей пише не ця заглушка, а сам розбір (`каталог_розбір._ОСОБЛИВОСТІ_*`,
# К-2): «чим ця річ відрізняється від інших речей з ТИМИ САМИМИ КОДАМИ… назва відтінку, яку дала
# крамниця (загальний колір уже несе `color_main`); фактура, переплетення, обробка поверхні;
# помітні деталі й фурнітура; особливості крою й посадки, яких не несуть коди».
# Перша версія заглушки робила навпаки — зшивала рядок із самих КОДІВ («stub, ring, gold,
# golden shade»), тобто міряла дублювання, яке власник 27.09 і наказав прибрати. Тепер рядок
# береться з трьох переліків слів, яких у жодному переліку кодів нема, стало за id речі: тип
# фактури, деталь чи фурнітура, назва відтінку крамниці. Довжина виходить у смузі справжнього
# рядка (приклад власника — 73 символи), і жодного коду речі в ньому нема.
ФАКТУРА = ("brushed surface", "chunky cable knit", "waffle weave", "crinkled finish",
           "sandwashed hand", "napped face", "slubby yarn", "matte crepe")
ДЕТАЛЬ = ("pearl buttons", "tonal topstitching", "ribbed cuffs", "covered placket",
          "raw hem", "piped seams", "tortoiseshell buckle", "concealed zip")
ВІДТІНОК = ("cappuccino", "oat milk", "burnt sugar", "sea glass", "dusty plum",
            "warm slate", "toasted almond", "faded indigo")


def _слова(ід):
    """Три вигадані фрагменти рядка особливостей — стало за id речі, без жодного коду речі."""
    ч = int(hashlib.sha1(("fe-%s" % ід).encode("utf-8")).hexdigest(), 16)
    return ["stub", ФАКТУРА[ч % len(ФАКТУРА)], ДЕТАЛЬ[(ч // 8) % len(ДЕТАЛЬ)],
            "%s shade" % ВІДТІНОК[(ч // 64) % len(ВІДТІНОК)]]


def рядок_особливостей(ід):
    """Вигаданий рядок особливостей речі: «stub», фактура, деталь, відтінок — ≤15 слів.

    Жодного коду речі в ньому нема НАВМИСНО (див. шапку переліків вище): рядок має нести те,
    чого коди не несуть, інакше вимір міряв би дублювання замість запису. Медіану довжини
    друкує проба — поруч із довжиною справжнього прикладу власника (73 символи)."""
    рядок = ", ".join(_слова(ід)[:15])
    return (рядок[:СТЕЛЯ_ОСОБЛИВОСТЕЙ].rsplit(",", 1)[0]
            if len(рядок) > СТЕЛЯ_ОСОБЛИВОСТЕЙ else рядок)


def розбори_н1(архів=СИРІ, модель=МОДЕЛЬ_СИРИХ):
    """[(id речі, поля розбору)] зі справжніх відповідей живого прогону — без моделі."""
    вих = []
    with tempfile.TemporaryDirectory() as тимч:
        with tarfile.open(архів) as т:
            т.extractall(тимч)
        теки = [т for т in glob.glob(os.path.join(тимч, "p3", "*")) if os.path.isdir(т)
                and модель in os.path.basename(т).lower()]
        мірка = json.load(io.open(os.path.join(теки[0], "прогін.json"), encoding="utf-8"))
        for р in мірка["речі"]:
            текст = io.open(os.path.join(теки[0], р["файл"]), encoding="utf-8").read()
            хвіст = текст.split("── ВІДПОВІДЬ", 1)
            поля, _ = КР.з_відповіді(хвіст[1]) if len(хвіст) > 1 else (None, None)
            if поля:
                вих.append((р["id"], поля))
    return вих


def зібрати(куди, скільки=None, архів=СИРІ):
    """Кладе файл {id: поля + features} на всі id каталогу. Повертає (шлях, речей, взірців)."""
    взірці = розбори_н1(архів)
    if not взірці:
        raise SystemExit("нема з чого робити заглушку: %s не дав жодного розібраного JSON" % архів)
    офери, _ = ФР.читати_yml(ФК.каталог_на_диску(), показ=False)
    ід = [o["id"] for o in офери][:скільки] if скільки else [o["id"] for o in офери]
    вих = {}
    for і in ід:
        поля = взірці[int(hashlib.sha1(str(і).encode("utf-8")).hexdigest(), 16) % len(взірці)][1]
        вих[і] = dict(поля, features=рядок_особливостей(і))
    os.makedirs(os.path.dirname(os.path.abspath(куди)) or ".", exist_ok=True)
    відкрити = gzip.open if куди.endswith(".gz") else io.open
    with відкрити(куди, "wt", encoding="utf-8") as ф:
        json.dump(вих, ф, ensure_ascii=False)
    return куди, len(вих), len(взірці)


def головна(арг=None):
    п = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    п.add_argument("--куди", default=os.path.join(tempfile.gettempdir(), КК.РОЗБІР_ІМ + ".gz"))
    п.add_argument("--скільки", type=int, default=None, help="лише перші N речей каталогу")
    к = п.parse_args(арг)
    шлях, речей, взірців = зібрати(к.куди, к.скільки)
    print("заглушка розбору: %d речей, %d справжніх взірців Н-1 → %s (%d КБ)"
          % (речей, взірців, шлях, os.path.getsize(шлях) // 1024))
    print("продукт візьме її так:  ROZBIR_KODY=%s ZAPYS_KOROTKYI=1 python3 …" % шлях)
    return 0


if __name__ == "__main__":
    sys.exit(головна())
