"""Повторює дві вставки перевірки #2424 на справжніх модулях без правки продукту."""
import importlib
import json
from pathlib import Path
import sys


def головна():
    """Підміняє лише розібране тіло жниварки й друкує два нові свідки п.4."""
    корінь = Path(__file__).resolve().parents[2]
    sys.path.insert(0, str(корінь / 'джерела/прилади'))
    п = importlib.import_module('корінь_річ_запис_речі')
    модулі, помилки, _, _ = п.побудувати_модулі(str(корінь))
    файл = 'zhnyvarka/жниварка.py'
    текст = (корінь / файл).read_text(encoding='utf8')
    маркер = '    if (not ф["опис"] or російське(ф["опис"])) and блок_опису is not None:'
    рядок = текст[:текст.index(маркер)].count('\n') + 1
    вставка = '    ф["проба_а"] = суп.get_text(" ")[:50]\n    ф["проба_б"] = bool(re.search(r"розпродано", суп.get_text(" ")))\n'
    новий = п.розібрати_py(файл, текст.replace(маркер, вставка + маркер, 1))
    модулі = [новий if м.файл == файл else м for м in модулі]
    а = п.Аналіз(модулі, п.Реєстр(str(корінь)))
    а.пройти()
    місця = п.обчислити(а)
    свідки = [dict(рядок=р, чому=ч, ланцюг=а.свідки[ф, р, пункт]) for (ф, р, пункт), ч in sorted(місця.items()) if ф == файл and пункт == 4 and р in (рядок, рядок + 1)]
    print(json.dumps(dict(нових_місць_п4=len(свідки), п4=sum(к[2] == 4 for к in місця), свідки=свідки, помилки=помилки), ensure_ascii=False, indent=1))
    return int(len(свідки) != 2)


if __name__ == '__main__':
    sys.exit(головна())
