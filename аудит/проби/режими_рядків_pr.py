"""CI рядка ЖИВИЙ ПІСЛЯ: режим кожного питання (поле «→ режим →») розбирає той самий код, що й `записати_план.py`
і `записати_сцену.py`; що прилад не виконає — вада рядка. Вхід: JSON-файл [{"id", "question", "line"}] (пише
`перевірити_тіло_pr.ps1`); код 1 — є вадні рядки."""
import json
from pathlib import Path
import sys

from записати_сцену import вхід_реєстру, режим_питання, змінні_режиму


def перевірити(рядки):
    """Повертає (id, режим, причина|None) для кожного рядка; питання без поля режиму — режим реєстру, вад нема."""
    підсумок = []
    for р in рядки:
        режим = режим_питання(р["question"])
        причина = None
        if режим is not None:
            try:
                змінні_режиму(р["id"], режим, вхід_реєстру(р["id"]))
            except ValueError as в:
                причина = str(в)
        підсумок.append((р["id"], режим, причина))
    return підсумок


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    підсумок = перевірити(json.loads(Path(sys.argv[1]).read_text(encoding="utf-8-sig")))
    for id_, режим, причина in підсумок:
        print(f"  ✗ вада: {причина}" if причина else f"  ✓ {id_} — режим {режим or 'реєстру'} виконується приладом")
    raise SystemExit(1 if any(п[2] for п in підсумок) else 0)
