#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Адреси переліку ПК-дотримання-правил: переведення з номерів рядків на цитати й стенд стійкості до зсуву рядків.

Наряд `ПК-перелік-адреси`. Рядок переліку `аудит/корені/ПК-дотримання-правил-перелік.md` адресував правило діапазоном
`файл:від–до`: вставка рядка вище за правило зсувала покриття й число місць без зміни правил (#2579: 189 → 194).
Нова адреса — `файл ‹початок› … ‹кінець› #відбиток` (прилад `джерела/прилади/корінь_пк_дотримання.py`, `знайти_адресу`).

  --перевести [--база SHA]  переводить перелік механічно: кожен діапазон `файл:від–до` — адреса тих самих рядків
                            поточного файлу правил (`адреса_рядків` приладу); решта рядка побайтово та сама; рядок,
                            чий діапазон — лише порожні рядки («не правило: порожній рядок»), прибрано: речень у ньому
                            нема (прилад їх не лічив і з номерами), а цитувати нічого. Адреси проби
                            `аудит/проби/пк_вибірка_в.py` — за правилом (стовпець «правило») переліку на коміті `--база`
                            цієї проби (2f7bcbdc): її діапазони відстали від перенумерації 050557ed.
  без ключів --до SHA       стенд: прилад і перелік з коміту SHA (номери рядків) і з робочого дерева (цитати) на копіях
                            файлів правил — як є; з порожніми рядками на початку й посередині кожного файлу; з рядками
                            тексту там само (між правилами); зі зміненим словом у середині правила. Код 0 — ДО на зсуві
                            змінює лічбу, ПІСЛЯ — ні; ПІСЛЯ на зміні правила — вада з адресою.
Запуск з кореня репозиторію: python3 -I аудит/проби/пк_адреси_переліку.py --до <SHA main до переходу>
"""
import argparse
import os
import re
import runpy
import shutil
import subprocess
import sys
import tempfile

КОРІНЬ = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
ПРИЛАД = "джерела/прилади/корінь_пк_дотримання.py"
ПЕРЕЛІК = "аудит/корені/ПК-дотримання-правил-перелік.md"
ВИБІРКА = "аудит/проби/пк_вибірка_в.py"
БАЗА_ВИБІРКИ = "2f7bcbdc"
П = runpy.run_path(os.path.join(КОРІНЬ, ПРИЛАД))


def git_show(sha, шлях):
    return subprocess.run(["git", "-C", КОРІНЬ, "show", f"{sha}:{шлях}"], capture_output=True, check=True,
                          text=True, encoding="utf-8").stdout


def нова_адреса(стара):
    м = П["СТАРА_АДРЕСА"].match(стара)
    return П["у_клітинку"](П["адреса_рядків"](м.group(1), int(м.group(2)), int(м.group(3) or м.group(2)), КОРІНЬ))


def перевести(база_вибірки):
    шлях = os.path.join(КОРІНЬ, ПЕРЕЛІК)
    рядки, вивід, змінено, прибрано = open(шлях, encoding="utf-8").read().split("\n"), [], 0, []
    for рядок in рядки:
        м = re.match(r"^\| ([^|]+?) \|", рядок)
        if м and П["СТАРА_АДРЕСА"].match(м.group(1)):
            try:
                рядок = "| " + нова_адреса(м.group(1)) + рядок[м.end(1):]
            except ValueError as е:
                if "нема непорожніх рядків" not in str(е):
                    raise
                прибрано.append(рядок)  # діапазон без тексту: речень у ньому нема, цілі для адреси теж
                continue
            змінено += 1
        вивід.append(рядок)
    open(шлях, "w", encoding="utf-8").write("\n".join(вивід))
    print(f"перелік: адрес переведено {змінено}; рядків без тексту прибрано {len(прибрано)}")
    for р in прибрано:
        print(f"    {р}")
    # Проба вибірки (в): діапазон її часу → правило → адреса того самого правила в переведеному переліку.
    with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False, encoding="utf-8") as ф:
        ф.write(git_show(база_вибірки, ПЕРЕЛІК))
    давні = {к[0]: к[1] for к in П["таблиці_переліку"](ф.name)[0]}
    os.unlink(ф.name)
    теперішні = П["таблиці_переліку"](шлях)[0]
    за_правилом = {к[1]: к[0] for к in теперішні}

    def слова(т):
        return set(re.findall(r"\w+", т.lower()))

    def найближча(стара):
        """Правило переписано після 2f7bcbdc: рядок того самого файлу з найбільшою часткою спільних слів правила."""
        старе = давні.get(стара)
        if старе is None:
            return None
        файл = стара.split(":")[0]
        оцінки = sorted(((len(слова(старе) & слова(к[1])) / len(слова(старе) | слова(к[1])), к[0], к[1])
                         for к in теперішні if к[0].startswith(файл + " ")), reverse=True)
        if not оцінки or оцінки[0][0] < 0.4:
            return None
        print(f"    {стара}: правило переписано — найближче ({оцінки[0][0]:.2f}): «{оцінки[0][2][:70]}»")
        return оцінки[0][1]
    шлях_в = os.path.join(КОРІНЬ, ВИБІРКА)
    текст = open(шлях_в, encoding="utf-8").read()
    нема = []

    def замінити(м):
        нова = за_правилом.get(давні.get(м.group(1))) or найближча(м.group(1))
        if нова is None:
            нема.append(м.group(1))
            return м.group(0)
        return '("' + нова.replace("\\", "\\\\").replace('"', '\\"') + '",'
    текст, н = re.subn(r'^    \("([\w.]+\.md:\d+(?:–\d+)?)",', замінити, текст, flags=re.M)
    open(шлях_в, "w", encoding="utf-8").write(текст)
    print(f"{ВИБІРКА}: адрес {н}, без правила в переліку {len(нема)} {нема}")
    return 1 if нема else 0


ФАЙЛИ = list(П["ФАЙЛИ_ПЕРЕЛІКУ"].values())


def межі_між_правилами(перелік, файл, рядків):
    """Номери рядків файлу (1-based), перед якими вставка не потрапляє всередину діапазону жодного рядка переліку."""
    зайняті = set()
    for к in П["таблиці_переліку"](перелік)[0] + [list(х) for х in П["таблиці_переліку"](перелік)[1]]:
        м = П["СТАРА_АДРЕСА"].match(к[0])
        if м and П["ФАЙЛИ_ПЕРЕЛІКУ"][м.group(1)] == файл:
            зайняті.update(range(int(м.group(2)) + 1, int(м.group(3) or м.group(2)) + 1))
    return [н for н in range(1, рядків + 2) if н not in зайняті]


def копія(дерево, прилад, перелік, зміна):
    """Тека з приладом, переліком, `.claude/settings.json` і хуками та файлами правил, змінними `зміна(шлях, рядки)`."""
    for шлях in [*ФАЙЛИ, ".claude/settings.json"]:
        рядки = open(os.path.join(КОРІНЬ, шлях), encoding="utf-8").read().split("\n")
        if шлях in ФАЙЛИ:
            рядки = зміна(шлях, рядки)
        os.makedirs(os.path.dirname(os.path.join(дерево, шлях)) or дерево, exist_ok=True)
        open(os.path.join(дерево, шлях), "w", encoding="utf-8").write("\n".join(рядки))
    shutil.copytree(os.path.join(КОРІНЬ, ".claude/хуки"), os.path.join(дерево, ".claude/хуки"), dirs_exist_ok=True)
    os.makedirs(os.path.join(дерево, os.path.dirname(ПРИЛАД)), exist_ok=True)
    open(os.path.join(дерево, ПРИЛАД), "w", encoding="utf-8").write(прилад)
    os.makedirs(os.path.join(дерево, os.path.dirname(ПЕРЕЛІК)), exist_ok=True)
    open(os.path.join(дерево, ПЕРЕЛІК), "w", encoding="utf-8").write(перелік)


def лічити(дерево):
    вихід = subprocess.run([sys.executable, "-I", ПРИЛАД, "--перелік", ПЕРЕЛІК], cwd=дерево, capture_output=True,
                           text=True, encoding="utf-8")
    рядки = вихід.stdout.strip().split("\n")
    підсумок = next((р for р in рядки if р.startswith("речень ")), "?")
    вади = [р for р in рядки if р.startswith("вада приладу")]
    return рядки[-1], підсумок, вади


def стенд(до):
    старий_прилад, старий_перелік = git_show(до, ПРИЛАД), git_show(до, ПЕРЕЛІК)
    новий_прилад = open(os.path.join(КОРІНЬ, ПРИЛАД), encoding="utf-8").read()
    новий_перелік = open(os.path.join(КОРІНЬ, ПЕРЕЛІК), encoding="utf-8").read()
    with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False, encoding="utf-8") as ф:
        ф.write(старий_перелік)
    межі = {ш: межі_між_правилами(ф.name, ш, len(open(os.path.join(КОРІНЬ, ш), encoding="utf-8").read().split("\n")))
            for ш in ФАЙЛИ}
    os.unlink(ф.name)

    def вставити(вставка):
        def зміна(шлях, рядки):
            між = межі[шлях]
            середина = min(між, key=lambda н: (abs(н - len(рядки) // 2), н))
            for н in sorted({1, середина}, reverse=True):
                рядки[н - 1:н - 1] = вставка(шлях, н)
            return рядки
        return зміна

    правило = ("AGENTS.md", "запускати `workflow_dispatch` чи auto-merge", "запускати `workflow_dispatch`, auto-merge")

    def змінити(шлях, рядки):
        if шлях == правило[0]:
            і = next(і for і, р in enumerate(рядки) if правило[1] in р)
            рядки[і] = рядки[і].replace(правило[1], правило[2])
        return рядки
    варіанти = [
        ("як є", lambda ш, р: р),
        ("порожні рядки на початку й посередині", вставити(lambda ш, н: ["", ""])),
        ("рядок тексту між правилами на початку й посередині", вставити(lambda ш, н: [f"Вставка стенда {н}.", ""])),
        (f"змінено слово правила {правило[0]} «{правило[1]}»", змінити),
    ]
    результат = {}
    for назва, зміна in варіанти:
        for мітка, прилад, перелік in (("ДО", старий_прилад, старий_перелік), ("ПІСЛЯ", новий_прилад, новий_перелік)):
            дерево = tempfile.mkdtemp(prefix="пк_адреси_")
            try:
                копія(дерево, прилад, перелік, зміна)
                результат[(назва, мітка)] = лічити(дерево)
            finally:
                shutil.rmtree(дерево, ignore_errors=True)
            місць, підсумок, вади = результат[(назва, мітка)]
            print(f"{назва} · {мітка}: {місць}; {підсумок}; вад {len(вади)}")
            for в in вади[:4]:
                print(f"    {в}")
            if len(вади) > 4:
                print(f"    … ще {len(вади) - 4}")
    вставок = 2 * len(ФАЙЛИ)
    було = результат[("як є", "ПІСЛЯ")]
    очікування = [
        ("ДО і ПІСЛЯ як є однакові", результат[("як є", "ДО")][:2] == було[:2]),
        ("ДО на порожніх рядках змінює лічбу", результат[(варіанти[1][0], "ДО")][:2] != було[:2]),
        ("ПІСЛЯ на порожніх рядках — побайтово як є", результат[(варіанти[1][0], "ПІСЛЯ")] == було),
        ("ДО на рядках тексту — непокриті не лише вставки",
         any("Вставка стенда" not in в for в in результат[(варіанти[2][0], "ДО")][2])),
        (f"ПІСЛЯ на рядках тексту — непокриті рівно {вставок} вставок, місць +{вставок}",
         len(результат[(варіанти[2][0], "ПІСЛЯ")][2]) == вставок
         and all("Вставка стенда" in в for в in результат[(варіанти[2][0], "ПІСЛЯ")][2])
         and int(результат[(варіанти[2][0], "ПІСЛЯ")][0].split()[-1]) == int(було[0].split()[-1]) + вставок),
        ("ДО на зміні правила — тиша (лічба як є)", результат[(варіанти[3][0], "ДО")][:2] == було[:2]),
        ("ПІСЛЯ на зміні правила — вада з файлом і адресою, місць більше",
         any(в.startswith("вада приладу: адреса не знаходить цілі: AGENTS.md ‹") and "текст правила змінено" in в
             for в in результат[(варіанти[3][0], "ПІСЛЯ")][2])
         and int(результат[(варіанти[3][0], "ПІСЛЯ")][0].split()[-1]) > int(було[0].split()[-1])),
    ]
    for що, добре in очікування:
        print(f"{'так' if добре else 'НІ'} · {що}")
    return 0 if all(д for _, д in очікування) else 1


def головна():
    п = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    п.add_argument("--перевести", action="store_true")
    п.add_argument("--база", default=БАЗА_ВИБІРКИ)
    п.add_argument("--до", default="", help="SHA main з переліком за номерами рядків (для стенда)")
    а = п.parse_args()
    if а.перевести:
        return перевести(а.база)
    if not а.до:
        п.error("потрібен --до <SHA> чи --перевести")
    return стенд(а.до)


if __name__ == "__main__":
    sys.exit(головна())
