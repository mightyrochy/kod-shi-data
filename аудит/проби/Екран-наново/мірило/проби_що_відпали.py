# -*- coding: utf-8 -*-
"""Мірило наряду Екран-наново, п.6: проби, що перестали працювати після перепису шару екрана, і чи запускає котрусь
із них CI, збірка, батарея чи обгортка ноутбука.

Відпале ім'я — глобальна функція чи змінна верхнього рівня, яку оголошував шар екрана `main` (`джерела/показ/*.js`,
вбудовані скрипти `джерела/показ.html`) і якої нема ніде в `джерела/показ/**` і `показ.html` гілки; відпалий вузол —
`id="…"` з `показ.html` `main`, назви якого нема ні в `показ.html`, ні в `джерела/показ/**` гілки. Проба відпала, коли згадує відпале ім'я словом чи відпалий вузол у
лапках. Запущене — файл, чиє ім'я названо в `.github/`, у файлах збірки й батареї (`джерела/*.py`, `джерела/*.js`,
`джерела/прилади/`), в обгортці (`аудит/адаптери/`) чи в порядку прогонів (`аудит/проби/живі_порядок.md`,
`записати_план.py`, `записати_сцену.py`, `приймання_записів.js`, `рв6_стенд.js`).
Запуск: python3 проби_що_відпали.py <дерево main> <дерево гілки>   (звіт — у stdout)"""
import os, re, sys, glob
до, після = sys.argv[1:3]
def текст(ш):
    try: return open(ш, encoding='utf8', errors='replace').read()
    except OSError: return ''
def шар(д):
    return [ф for ф in glob.glob(os.path.join(д, 'джерела/показ/**/*.js'), recursive=True)] + [os.path.join(д, 'джерела/показ.html')]
ОГОЛ = re.compile(r'^(?:async\s+)?function\s*\*?\s*([A-Za-zА-Яа-яІіЇїЄєҐґʼ_$][\wА-Яа-яІіЇїЄєҐґʼ$]*)|^(?:var|let|const)\s+([A-Za-zА-Яа-яІіЇїЄєҐґʼ_$][\wА-Яа-яІіЇїЄєҐґʼ$]*)', re.M)
def імена(д):
    і = set()
    for ф in шар(д):
        for м in ОГОЛ.finditer(текст(ф)): і.add(м.group(1) or м.group(2))
    return і
def вузли(д): return set(re.findall(r'\bid="([^"]+)"', текст(os.path.join(д, 'джерела/показ.html'))))
усе_після = '\n'.join(текст(ф) for ф in шар(після))
СЛОВО = r'(?<![\wА-Яа-яІіЇїЄєҐґʼ$]){}(?![\wА-Яа-яІіЇїЄєҐґʼ$])'
відпалі_імена = sorted(і for і in імена(до) - імена(після) if len(і) > 3 and not re.search(СЛОВО.format(re.escape(і)), усе_після))
# вузол, який гілка будує з коду чи тримає в частині шаблона, не відпав: його назва є в шарі гілки
усе_після_шар = усе_після + '\n'.join(текст(ф) for ф in glob.glob(os.path.join(після, 'джерела/показ/**/*'), recursive=True) if os.path.isfile(ф))
відпалі_вузли = sorted(в for в in вузли(до) - вузли(після) if в not in усе_після_шар)
проби = [ф for к in ('аудит/проби', 'джерела/проби') for ф in glob.glob(os.path.join(після, к, '**/*'), recursive=True)
         if os.path.isfile(ф) and re.search(r'\.(c?js|mjs|py)$', ф) and '/Екран-наново/' not in ф and '/node_modules/' not in ф]
запускачі = [ф for зр in ('.github/**/*', 'джерела/*.py', 'джерела/*.js', 'джерела/прилади/*', 'аудит/адаптери/**/*', 'аудит/проби/живі_порядок.md',
             'аудит/проби/записати_план.py', 'аудит/проби/записати_сцену.py', 'аудит/проби/приймання_записів.js', 'аудит/проби/рв6_стенд.js', 'аудит/КОД.md')
             for ф in glob.glob(os.path.join(після, зр), recursive=True) if os.path.isfile(ф)]
тексти_запускачів = {ф: текст(ф) for ф in запускачі}
def хто_запускає(проба):
    # назва з текою («3.2-Б/картка.js»): саме ім'я файла («знімок.js», «картка.js») мають десятки проб
    ч = os.path.relpath(проба, після).split(os.sep); ім = '/'.join(ч[-2:]) if len(ч) > 3 else ч[-1]
    return sorted(os.path.relpath(ф, після) for ф, т in тексти_запускачів.items() if ім in т and os.path.abspath(ф) != os.path.abspath(проба))
рядки = []
for п in sorted(проби):
    т = текст(п)
    ім = [і for і in відпалі_імена if re.search(СЛОВО.format(re.escape(і)), т)]
    вз = [в for в in відпалі_вузли if re.search(r'''['"`#]''' + re.escape(в) + r'''['"`]''', т)]
    if ім or вз: рядки.append((os.path.relpath(п, після), ім, вз, хто_запускає(п)))
print(f'відпалих імен шару екрана: {len(відпалі_імена)}; відпалих вузлів `показ.html`: {len(відпалі_вузли)}; проб переглянуто: {len(проби)}; проб, що згадують відпале: {len(рядки)}; з них запускає CI, збірка, батарея чи обгортка: {sum(1 for р in рядки if р[3])}')
print('\nвідпалі вузли: ' + (', '.join(відпалі_вузли) or 'нема'))
print('\n| проба | відпалі імена | відпалі вузли | хто запускає |\n|---|---|---|---|')
for п, ім, вз, хто in рядки:
    print(f"| `{п}` | {', '.join(ім[:6])}{' … ще ' + str(len(ім) - 6) if len(ім) > 6 else ''} | {', '.join(вз[:6])}{' … ще ' + str(len(вз) - 6) if len(вз) > 6 else ''} | {', '.join(хто) or '—'} |")
