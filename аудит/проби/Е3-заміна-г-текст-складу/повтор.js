/* Частина `повтор.py`: справжній етап фото-заміни показу ДО (origin/main) і ПІСЛЯ (робоче дерево) над записаними
   рішенням коду й прозою відповіді, що несла `swap`. Опис вирішеного складу (ПІСЛЯ) — заглушка «ОПИС СКЛАДУ»:
   його пише модель, повтор перевіряє, чий текст іде на картку. */
const fs = require('fs');
const [файл, старий, новий] = process.argv.slice(2);
const етап = к => { const код = fs.readFileSync(к, 'utf8');
  return new (Object.getPrototypeOf(async function(){}).constructor)('ctx', 'with(ctx){' +
    код.slice(код.indexOf('    const зам4 ='), код.indexOf('    вхОпису = {...вхОпису, заміна_вирішена: 1}')) +
    '; return {в4, обраніІД, замінаФото};}'); };
async function прогнати(ф, в){
  const ctx = {в4:{заміна:в.перше, опис:{текст:в.проза, як_носити:в.як}, мова_повтор:{спроб_усього:1}},
    замінаФото:null, ЗБ:{діагноз:[]}, фотоПоказано:true, обраніІД:['інша', в.перше.річ], т4:в.проза, в:null, текст:'',
    підпис:'п', вхідОпису:{речі:['інша', в.перше.річ]}, вхОпису:{ід:['інша', в.перше.річ]}, пвн:{номери:{}},
    оголКартки:[], дібраніКодом:{}, свідоміКартки:[], свідоміКарткиІд:[], описНеДійшов:null, ФОРМА_ОПИСУ_П:'форма',
    показатиТокени(){}, малюватиТокениП(){}, підписатиКадри:()=>[], кадриЗАдрес:async()=>[], шаблонОписуП:в=>в,
    містП:async(що,вх)=>({промпт:вх.заміна ? 'вибір' : 'ОПИС СКЛАДУ', фото:[]}),
    модельРукиП:async б=>б[б.length-1].text,
    к:{рука:'1', лічильники:{викликів:0}, станОбриву:()=>({}), зОбривом:(_,x)=>x, запамʼятатиЗапит(){},
      відМоделіРуки:async x=>x.заміна_запасні ? {заміна:в.друге}
        : {перевірено:true, речі:x.ід.map(id=>({id})), опис:{текст:'ОПИС СКЛАДУ ' + x.ід.join('+'), як_носити:[]}}}};
  return ф(ctx);
}
(async()=>{
  const випадки = JSON.parse(fs.readFileSync(файл, 'utf8')), ДО = етап(старий), ПІСЛЯ = етап(новий);
  const лік = {сцен:0, до_проза:0, після_проза:0, не_застосовано:0, після_бракує:0, форма:0};
  for (const в of випадки){
    if (!в.проза) { console.log(в.тека.padEnd(58), '| записаної прози з swap нема — пропущено'); continue; }
    const до = await прогнати(ДО, в), після = await прогнати(ПІСЛЯ, в);
    const застосовано = після.обраніІД.includes('нова');
    const ряд = ((після.замінаФото || {}).текст || {}).statements || [];
    лік.сцен++; if (до.в4.опис.текст === в.проза && !до.обраніІД.includes('нова')) лік.до_проза++;
    if (після.в4.опис.текст === в.проза) лік.після_проза++;
    if (!застосовано){ лік.не_застосовано++; if (ряд.some(с => с.code === 'photo_item_unfit_no_swap')) лік.після_бракує++; }
    if (в.перше.відмова === 'reason_not_in_list') лік.форма++;
    console.log(в.тека.padEnd(58), '| рішення', (в.друге || в.перше).стан.padEnd(9), (в.перше.відмова || '').padEnd(19),
      '| ДО картка:', до.в4.опис.текст === в.проза ? 'проза пропозиції' : JSON.stringify(до.в4.опис.текст).slice(0,30),
      '| ПІСЛЯ картка:', JSON.stringify(після.в4.опис.текст).slice(0,40), '| рядок:', (ряд[0] || {}).code || '—');
  }
  console.log('ПІДСУМОК', JSON.stringify(лік));
})().catch(е=>{console.error(е); process.exitCode=1;});
