        import сценарій as СЦ
        import річ_з_фото as РФ
        типова = (п.get("джерело_полів") or {}).get("нагода") == ПН.ТИПОВА_НАГОДА_РЕЧІ
        # Ч-1 (п.12): вердикт — заяви кодами, рядка «рядок» у ньому нема з 26.09 (доти тут був KeyError)
