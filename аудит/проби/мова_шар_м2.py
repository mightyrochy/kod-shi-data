        підсумок["не_назвала"] = "occasion_not_named_everyday" in [
            з["code"] for з in ((ве.get("повідомлення") or {}).get("statements") or [])]
        підсумок["типова"] = типова
        # Ч-5: та сама відповідь перекладача БЕЗ фото — перекладач фото не бачить, різницю робить лише код
