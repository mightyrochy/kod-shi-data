def вибірка():
    """Вибірка продукту (`мовний_шар.ВИБІРКА`); TEMPERATURA — свідомий дослід поверх неї."""
    в = dict(МШ.ВИБІРКА)
    if os.environ.get("TEMPERATURA"):
        в["temperature"] = float(os.environ["TEMPERATURA"])
    return в


def дзвінок(модель, промпт):
    тіло = dict(model=модель, max_tokens=4000, stream=False, messages=[dict(role="user", content=промпт)],
                **вибірка())
    if not os.environ.get("THINK"):
        тіло["reasoning_effort"] = "none"
    зап = urllib.request.Request(os.environ.get("MODEL_URL", "http://127.0.0.1:1234/v1").rstrip("/")
                                 + "/chat/completions", json.dumps(тіло).encode("utf-8"),
                                 {"Content-Type": "application/json"})
    т0 = time.time()
    відп = json.load(urllib.request.urlopen(зап, timeout=1800))["choices"][0]["message"].get("content") or ""
    return відп, time.time() - т0


def майже(цитата, слова):
    """Та сама механіка, що в `мова_сторож_н1.py`: кожне слово цитати (≥ 4 знаки) стоїть у її
    словах початком якогось слова — модель процитувала майже дослівно."""
    ц, т = МШ._до_звірки(цитата), МШ._до_звірки(слова)
    слова_ц = [с for с in ц.split() if len(с) >= 4]
    return bool(слова_ц) and all(re.search(r"(^| )" + re.escape(с[:max(4, len(с) - 2)]), т) for с in слова_ц)


def цитата_поля(поле, значення, цитати):
    """Цитата, на якій стоїть поле, — так само, як її бере `_тримається`."""
    if поле in МШ._РЕЧІ_З_ЦИТАТОЮ and isinstance(значення, list):
        return [(р.get("quote") or ((р.get("name") or {}).get("free_text")
                if поле == "own_items" else None) or цитати.get(поле)) for р in значення]
    return [цитати.get(поле)]


def парою(сире):
    """Скільки полів відповіді модель написала парою {quote, value|code}."""
    об, _ = МШ._обʼєкт(сире)
    return sum(1 for v in об.values() if isinstance(v, dict) and "quote" in v
               and any(к in v for к in МШ._ЗНАЧЕННЯ_ПАРИ)) if isinstance(об, dict) else 0


