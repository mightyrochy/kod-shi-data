# -*- coding: utf-8 -*-
"""Е3-одна-величина ч28 (п.7, слово довжини крамниці → запис точки речі): клас і край речей зі словом ДО → ПІСЛЯ.

Запуск із кореня репозиторію (каталог розпаковано: `python3 -c "import чистка_каталогу as ч; ч.забезпечити_чистим(
'каталог_повний.xml')"` у `джерела/`):
    python3 аудит/проби/Е3_ч28_слово_довжини.py                       # ПІСЛЯ: код цієї гілки
    git worktree add /tmp/до <SHA_ДО>
    python3 аудит/проби/Е3_ч28_слово_довжини.py --код /tmp/до/джерела  # ДО: той самий скрипт на старому коді

Каталог — `джерела/каталог_повний.xml` цього клону через живий `bridge.виклик("запити")` стенда; модель і платні API не
викликаються. Тіла — 155/165/175 см (обхвати 98/92/74/100, як у `Е3_ч26_клас_довжини.py`). Друкує:
  · таблиці слів `фід_атрибути` (`ДОВЖИНА_PARAM`, `ДОВЖИНА_КЛЮЧІ_ОДЯГ`, `ВІДНОСНІ_ЗА_СЛОТОМ`): слово → що в таблиці, клас
    речі (`довжина_рівень`) і центр краю на тілах;
  · клас, який несе поле `довжина_рівень` каталогу: (слот, звідки слово, клас) — лічба речей;
  · речі зі словом довжини без довжини виробу: (зріст, клас, півширина, похибка краю, смуга графа), K-FIT-03 `fit.краї`,
    K-SIL-02 `fit.поділ_образу`."""
import sys, pathlib, json, collections, os, io, contextlib

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
код = pathlib.Path(sys.argv[sys.argv.index("--код") + 1]).resolve() if "--код" in sys.argv else КОРІНЬ / "джерела"
os.chdir(код); sys.path.insert(0, str(код))
import feed as Ф, bridge as B, composer as КМ, fit as ПС, graph as Г, композитор_річ as КР, фід_атрибути as А

вх = json.load(open(код / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску(str(КОРІНЬ / "джерела" / "каталог_повний.xml")); вх["гілка"] = 0
with contextlib.redirect_stdout(io.StringIO()):
    json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
print(f"код: {код}  · речей каталогу {len(кат)}")
ОБХВАТИ = dict(плечі=98, груди=92, талія=74, стегна=100)
ТІЛА = {зр: ПС.тіло(зр, ОБХВАТИ) for зр in (155, 165, 175)}
клас_з = getattr(А, "клас_довжини", lambda х: х)       # ПІСЛЯ: таблиці несуть імена записів, клас — похідна


def центр(клас, t):
    в, р = КР.висота_рівня(клас, t["висоти"]) if клас in КР.РІВЕНЬ_ЗОНА else (None, None)
    return "%s ± %s" % (в, р)


print("слово → таблиця (що в ній) → клас речі → центр ± півширина краю на 155 / 165 / 175")
рядки = [("param", с, з) for с, з in А.ДОВЖИНА_PARAM.items()]
рядки += [("назва", " | ".join(кл), к) for к, кл in А.ДОВЖИНА_КЛЮЧІ_ОДЯГ]
рядки += [("відносне", "%s·%s" % с, з) for с, з in А.ВІДНОСНІ_ЗА_СЛОТОМ.items()]
for звідки, слова, в in рядки:
    к = клас_з(в)
    print("   %-9s %-46s %-16s → %-9s %s" % (звідки, слова[:46], в, к, " / ".join(центр(к, t) for t in ТІЛА.values())))

друк_н = collections.Counter(
    (c.get("слот"), "param" if str(c.get("довжина_джерело") or "").startswith("param") else
     ("слово назви" if c.get("довжина_джерело") == "слово назви" else str(c.get("довжина_джерело") or "—")[:12]),
     c.get("довжина_рівень")) for c in кат if c.get("довжина_рівень"))
print("клас в каталозі: (слот, звідки, клас) — речей")
for к, v in sorted(друк_н.items(), key=lambda x: (str(x[0][0]), str(x[0][1]), -x[1])):
    print("   %6d  %s" % (v, к))
парам = collections.Counter(
    (str(c.get("довжина_джерело")).split("«")[-1].rstrip("»"), c.get("слот"), c.get("довжина_рівень"))
    for c in кат if str(c.get("довжина_джерело") or "").startswith("param"))
print("param-слова: (слово, слот, клас) — речей")
for к, v in sorted(парам.items(), key=lambda x: (x[0][0], str(x[0][1]))):
    print("   %6d  %s" % (v, к))

ключ = lambda z: (z["правило"], z["сила"], tuple(sorted(з["code"] for з in (z.get("заяви") or []))))
слово = [c for c in кат if c.get("довжина_рівень") and c.get("довжина_виробу_см") is None
         and c.get("слот") in ("низ", "сукня", "комплект", "верхній_шар", "верх")]
print(f"речей зі словом довжини без довжини виробу: {len(слово)}")
краї, k03к, k02 = (collections.Counter() for _ in range(3))
for зр, t in ТІЛА.items():
    with contextlib.redirect_stdout(io.StringIO()):
        рс = [р for р in (КМ.у_річ(dict(c), c["слот"], t) for c in слово) if р]
        for р in рс:
            пк = ПС.похибка_краю(t, р)
            краї[(зр, р.get("довжина_рівень"), р.get("край_розкид_см"),
                  "похибка краю відома" if пк is not None else "похибка краю невідома",
                  "смуга в графі" if "край" in Г.зона(р) else "смуги нема")] += 1
            for z in ПС.краї(t, [р]):
                k03к[(зр,) + ключ(z)] += 1
            if р.get("слот") in ("верх", "верхній_шар"):
                for z in ПС.поділ_образу(t, [р]):
                    k02[(зр,) + ключ(z)] += 1
for назва, л in (("край зі слова: (зріст, клас, півширина, похибка краю, смуга графа)", краї),
                 ("K-FIT-03 fit.краї по одній речі зі словом: (зріст, правило, сила, заяви)", k03к),
                 ("K-SIL-02 fit.поділ_образу по одній верхній речі зі словом: (зріст, правило, сила, заяви)", k02)):
    print(назва + ":")
    for к, v in sorted(л.items(), key=lambda x: (str(x[0][0]), -x[1], str(x[0]))):
        print(f"   {v:6d}  {к}")
