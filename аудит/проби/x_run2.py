def _показ(мітка, зн):
    if not зн:
        print("%s не спрацювало" % мітка)
        return None
    з = зн[0]
    print("%s блокує=%s  сила=%s  регістр=%s%s"
          % (мітка, з.get("блокує"), з.get("сила"), з.get("регістр"),
             ("  ← " + з["гейт_знято"]) if з.get("гейт_знято") else ""))
    if з.get("стеля_тіру"):
        print("      %s" % з["стеля_тіру"])
    return з.get("блокує")

