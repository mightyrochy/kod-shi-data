class Рядок(dict):
    """Рядок пулу, що пише, хто його копіює і хто читає з нього поле запису каталогу (`_кат`)."""
    def _поле(self, к):
        if к in self.__dict__.get("_кат", ()) and not dict.__contains__(self, к):
            ЛОГ[("поле",) + _місце() + (к,)] += 1

    def keys(self):
        ЛОГ[("копія",) + _місце() + ("",)] += 1
        return dict.keys(self)

    def __iter__(self):
        ЛОГ[("копія",) + _місце() + ("",)] += 1
        return dict.__iter__(self)

    def get(self, к, д=None):
        self._поле(к)
        return dict.get(self, к, д)

    def __getitem__(self, к):
        self._поле(к)
        return dict.__getitem__(self, к)

    def __contains__(self, к):
        self._поле(к)
        return dict.__contains__(self, к)


