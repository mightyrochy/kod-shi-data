"""МІРИЛО Е2-втрата-слова-оцінка-питає (дошка 16498, 16415): чи картка оцінки питає жінку тим самим повідомленням,
що картка рук 1–2, і чи журнальні заяви правил не доходять до неї «входами».

Ті самі п'ять сцен, що в `Е2-втрата-слова-суд-дороги-питання/питання_часу.py` (три без часу на ногах, два контролі).
Для кожної: заява часу K-END-01 → повідомлення `card_unchecked` картки рук 1–2 (`міст_відповіді`) і те, що несе
картка оцінки (`оцінка_образу.прийняти_оцінку`, `не_знаю[]`). Слова питанню пише один шлях показу (`питаннямиП`) з
повідомлення: збігається повідомлення — збігаються й слова. Журнальні рядки на картці — входи з кодами заяв, адресованих
журналу (`внутрішня_мова.МЕТАДАНІ_ЗАЯВ`), що йдуть у рядок «no input: …» (`rule_input_missing`, `cannot_tell_*`…).

Запуск з кореня: `python3 -W ignore аудит/проби/Е2-втрата-слова-оцінка-питає/питання_оцінки.py`. Останній рядок —
`сцен без часу: N · повідомлення оцінки = рук 1–2: A · заяв жінці на картці оцінки без повідомлення: B ·
журнальних входів на картці оцінки: C`."""
import json, os, sys
КОРІНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
sys.path.insert(0, os.path.join(КОРІНЬ, 'джерела'))
os.chdir(os.path.join(КОРІНЬ, 'джерела'))
import аксесуари_носіння as АН, міст_відповіді as М, оцінка_образу as О, внутрішня_мова as ВМ, colorspace as cs

СЦЕНИ = [("нічого не назвала", {}), ("бруківка без часу", {"поверхня": "бруківка"}),
         ("сніг з погоди без часу", {"опади": "сніг"}),
         ("контроль: 20 хв пішки", {"дорога_пішки_хв": 20}), ("контроль: 8 год", {"тривалість_год": 8})]
ПАРА = [dict(id="туфлі-1", слот="взуття", назва="туфлі на шпильці"), dict(id="сумка-1", слот="сумка", назва="сумка")]
вх = json.load(open('стенд_вх.json'))
ФОТО = [('ф1', 'жакет', 'верхній_шар', '#7d7f63', 'хакі'), ('ф3', 'міні-спідниця', 'низ', '#6b1f2a', 'бордовий'),
        ('ф5', 'туфлі на шпильці', 'взуття', '#e6dfd2', 'вершковий')]
речі_фото = [dict(ід=і, фото=і, назва=н, слот=с, колір=к, ошатність=6, в_образі=True,
                  вимір=dict(lab=list(cs.hx(h)), hex=h, слово=к)) for і, н, с, h, к in ФОТО]
без_часу = збіг = без_повід = журнальних = 0
for назва, сц in СЦЕНИ:
    зн = АН.вартість_носіння(ПАРА, тривалість_год=сц.get("тривалість_год"), поверхня=сц.get("поверхня"),
                             дорога_пішки_хв=сц.get("дорога_пішки_хв"), опади=сц.get("опади"))
    питання = [z for z in зн if z.get("правило") == "K-END-01" and z.get("сила") == "питання"]
    рука = [М._з_кодами(М._питання_кодами(z), {}.get) for z in питання]
    с = О.суд(dict(вх, речі=речі_фото, сценарій_оцінки=dict(сц), крамниця=False))
    не_знаю = О.прийняти_оцінку(json.dumps({"answer": "Ок.", "verdict": "wear_as_is"}), с)["картка"]["не_знаю"]
    оцінка = [х["повідомлення"] for х in не_знаю if х.get("повідомлення")]
    за_кодом = lambda ms: sorted(json.dumps(m, sort_keys=True, ensure_ascii=False) for m in ms
                                 if any(з.get("code", "").startswith("wear_cost_no_duration") for з in m["statements"]))
    жур = [в for х in не_знаю for в in х.get("входи") or [] if (ВМ.МЕТАДАНІ_ЗАЯВ.get(в) or {}).get("recipient") == "journal"]
    без_повід += sum(1 for х in не_знаю for в in х.get("входи") or [] if в.startswith("wear_cost_no_duration"))
    журнальних += len(жур)
    print("%s · рука: %d повід. часу · оцінка: %d повід. часу, збігаються: %s · журнальні входи на картці: %s" % (
        назва, len(за_кодом(рука)), len(за_кодом(оцінка)), за_кодом(рука) == за_кодом(оцінка) and bool(за_кодом(рука)),
        жур or "—"))
    if питання:
        без_часу += 1
        збіг += за_кодом(рука) == за_кодом(оцінка) and bool(за_кодом(рука))
print("сцен без часу: %d · повідомлення оцінки = рук 1–2: %d · заяв жінці на картці оцінки без повідомлення: %d · "
      "журнальних входів на картці оцінки: %d" % (без_часу, збіг, без_повід, журнальних))
