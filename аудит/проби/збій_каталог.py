"""Прилад стенда, не код продукту: бита річ каталогу для сцени `ж7_збій_битої_речі` (корінь Е2-збій-без-сліду).

Стенд (`рв6_стенд.js` з `ZBIJ=katalog`, модуль `збій_наведення.js`) кладе цей файл у ФС воркера Pyodide й після палітри,
до «Зібрати образи», кличе `навести(<фікстура>)`: у кешованій базі каталогу (`фід_каталог.КЕШ_БАЗИ`, ту саму базу
бере збирання) речі фікстури ставляться биті поля, а пакети, зібрані до того (палітра), скидаються — збирання будує пул
наново й несе биту річ до правил. Файл каталогу й вантаж сторінки не змінюються.
`стан(id)` — що в базі лежить після збирання (чи наведене пережило перезапуск воркера);
`кандидати()` — пари, у яких підбор видно лише числом `каблук_см` (так фікстуру й обрано).
"""
import json
import re

import profile as _П
import фід_каталог as _Ф


def _записи():
    for _зб, б, _сл in list(_Ф.КЕШ_БАЗИ.values()):
        yield from (б or {}).get("каталог") or []


def _зріз(р, поля):
    return {к: р.get(к) for к in ("id", "назва", "слот", "тип", "каблук", "каблук_є", "каблук_клас", "каблук_від", "каблук_до", *поля)}


def кандидати(n=12):
    """Пари, де підбор знає лише висота: ні тип, ні назва його не кажуть. `каблук` (True/False) і `каблук_клас` фід
    виводить із тієї самої висоти, тож бита висота в такої пари не дає й їх (фікстура ставить їм None) — межа «без
    підборів» лишається без доказу, і предикат читає саме `каблук_см`. Чоботи й черевики — першими (сцена — мороз)."""
    вих = []
    for р in _записи():
        if р.get("слот") != "взуття" or р.get("каблук_є") is True:
            continue
        try:
            см = float(р.get("каблук_см") or 0)
        except (TypeError, ValueError):
            continue
        if см <= 0 or _П._каблук_за_типом(р) or re.search(r"каблук|підбор|шпильк|танкет", str(р.get("назва") or ""), re.I):
            continue
        вих.append(_зріз(р, ("каблук_см", "сезон_тканини", "ціна")))
    вих.sort(key=lambda р: not re.search(r"чобот|черевик|ботильйон|челсі", str(р.get("назва") or "") + str(р.get("тип") or ""), re.I))
    взуття = [р for р in _записи() if р.get("слот") == "взуття"]
    return json.dumps({"усього": len(вих), "перші": вих[:n], "баз": len(_Ф.КЕШ_БАЗИ), "взуття": len(взуття),
                       "з_каблук_см": sum(1 for р in взуття if р.get("каблук_см") not in (None, "", 0))}, ensure_ascii=False)


def навести(фікстура):
    ф = json.loads(фікстура) if isinstance(фікстура, str) else фікстура
    поля = ф["поля"]
    знайдено = [р for р in _записи() if р.get("id") == ф["id"]]
    до = [_зріз(р, поля) for р in знайдено]
    for р in знайдено:
        р.update(поля)
    import міст_пакет as _МП
    пакетів = len(_МП.КЕШ_ПАКЕТА)
    _МП.КЕШ_ПАКЕТА.clear()
    return json.dumps({"баз": len(_Ф.КЕШ_БАЗИ), "знайдено": len(знайдено), "до": до,
                       "після": [_зріз(р, поля) for р in знайдено], "скинуто_пакетів": пакетів}, ensure_ascii=False)


def стан(ід):
    return json.dumps({"баз": len(_Ф.КЕШ_БАЗИ), "речі": [_зріз(р, ("каблук_см", "сезон_тканини")) for р in _записи()
                                                       if р.get("id") == ід]}, ensure_ascii=False)
