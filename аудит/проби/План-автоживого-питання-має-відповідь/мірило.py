#!/usr/bin/env python3
"""Мірило наряду «План-автоживого-питання-має-відповідь»: що новий план живого робить із питаннями п'яти оцінок 13–18.11.

Рядки «не виміряно» й класи — прилади звіту #4274 (`../Автоживий-не-виміряно-розклад/витяг.py`, `класи.py`, `повтори.py`);
правила плану — Python-повтор обгортки з `джерела/прилади/живий_після_прогнано.py` (`непридатне_питання` =
Get-LiveQuestionUnfit, `без_відповіді_оцінок` = Get-AutoEvalUnanswered, `прогнані_записами` = Get-AutoRanPairs; паритет —
`тест_живий_після_прогнано.py` у CI з pwsh). Для кожного рядка — пара (PR, сцена) і її нинішні рядки `ЖИВИЙ ПІСЛЯ` з тіл PR:
- «відсіє до прогону» — Get-LiveQuestionUnfit дає причину на сам текст (без оцінки);
- «bad: не виміряно» — запис пари є, оцінка його теки дала «не виміряно», текст той самий;
- «у план» — запису, що відповів, нема (рядок змінено, запис неповний чи rc поза 0–1);
- «відповідь в іншій оцінці» — запис пари з теки однієї з п'яти оцінок, де оцінка дала «так» чи «ні»;
- «прогнано заново, чекає оцінки» — інший запис пари на коді з PR, теку якого ще не оцінено.
Запуск з кореня репозиторію: python3 аудит/проби/План-автоживого-питання-має-відповідь/мірило.py <тіла.json> [--рядки]
(тіла — відповіді `gh api -X GET search/issues` з PR, злитими від 01.11, підряд в одному файлі)."""
import collections
import json
import os
import re
import subprocess
import sys

КОРІНЬ = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True, check=True).stdout.strip()
os.chdir(КОРІНЬ)
sys.path.insert(0, "джерела/прилади")
import живий_після_прогнано as ж  # noqa: E402

РОЗКЛАД = "аудит/проби/Автоживий-не-виміряно-розклад"
ТЕКИ = {"О1113": "Е1-нічний-живий-20261113", "Х1115": "автоживий-eebb37ae0aa73a0b429898cf7a6bca4daecfb462",
        "Е1115": "Е1-нічний-живий-20261115", "Х1811": "Тестовий-прогін-хмара-1811",
        "Х1811р": "Тестовий-прогін-хмара-1811-ранок"}


ДОЛІ = ["відсіє до прогону", "bad: не виміряно", "у план", "відповідь в іншій оцінці", "прогнано заново, чекає оцінки"]


def рядки_оцінок():
    """Рядки п'яти оцінок із класом причини — дослівно прилади #4274 (запуск з `аудит/`)."""
    витяг = subprocess.run([sys.executable, os.path.join(КОРІНЬ, РОЗКЛАД, "витяг.py")], cwd="аудит",
                           capture_output=True, text=True, check=True).stdout
    шлях = "/tmp/мірило_рядки.json"
    with open(шлях, "w", encoding="utf-8") as ф:
        ф.write(витяг)
    sys.argv[1:] = [шлях]
    sys.path.insert(0, os.path.join(КОРІНЬ, РОЗКЛАД))
    поточна = os.getcwd()
    os.chdir("аудит")
    try:
        import класи  # noqa: E402
    finally:
        os.chdir(поточна)
    return json.loads(витяг)["усі"], класи.ряд


def тіла(шлях):
    текст, декодер, і, пункти = open(шлях, encoding="utf-8").read(), json.JSONDecoder(), 0, []
    while і < len(текст):
        while і < len(текст) and текст[і].isspace():
            і += 1
        if і >= len(текст):
            break
        об, і = декодер.raw_decode(текст, і)
        пункти += об.get("items", []) if isinstance(об, dict) else об
    return {str(п["number"]): п.get("body") or "" for п in пункти}


def main():
    тіла_pr = тіла(sys.argv[1])
    друк_рядків = "--рядки" in sys.argv
    усі, нв = рядки_оцінок()
    реєстр_текст = ж.прочитати_файли("HEAD", [ж.РЕЄСТР_ШЛЯХ])[ж.РЕЄСТР_ШЛЯХ]
    реєстр, входи = ж.реєстр_сцен(реєстр_текст), ж.входи_сцен(реєстр_текст)
    записи = ж.прогнані_записами("HEAD")
    оцінки = ж.без_відповіді_оцінок("HEAD")
    злиття = {}
    for рядок in subprocess.run(["git", "log", "--first-parent", "--format=%H %s", "HEAD"], capture_output=True,
                                text=True, check=True).stdout.splitlines():
        sha, _, тема = рядок.partition(" ")
        м = ж.ТЕМА_PR.search(тема) or ж.ЗЛИТТЯ_PR.match(тема)
        if м:
            злиття.setdefault(м.group(1), sha)
    кеш = {}

    def доля(r):
        pr, сцена = r["pr"], re.match(r"^[^\s(]+", r["сцена"].strip("`")).group(0)
        if pr not in тіла_pr:
            return "тіла PR нема у файлі", ""
        пункти = [п for п in ж.рядки_живий_після(тіла_pr[pr], реєстр) if п["id"] == сцена and not п["error"]]
        if not пункти:
            return "рядка в тілі нема", ""
        результати = []
        for п in пункти:
            хмара = п["mode"].startswith("функція")
            відповіли, відкриті = [], []
            for з in ([] if хмара else записи.get(f"{pr}|{сцена}", [])):
                if pr not in злиття or not ж.є_предком(злиття[pr], з["sha"], кеш):
                    continue
                о = оцінки.get(f"{з['звіт']}|{pr}|{сцена}")
                (відкриті if о else відповіли).append((з, о))
            if відповіли:
                тека = відповіли[0][0]["звіт"]
                результати.append(("відповідь в іншій оцінці" if тека in ТЕКИ.values() else "прогнано заново, чекає оцінки", тека))
                continue
            причина = "" if хмара else ж.непридатне_питання(п["question"], п["mode"], входи.get(сцена, ""))
            if причина:
                результати.append(("відсіє до прогону", причина))
                continue
            той = next((о for з, о in відкриті if з["питання"] == п["question"]), None)
            if той and not той["обрив"]:
                результати.append(("bad: не виміряно", той["де"]))
            else:
                результати.append(("у план", "обрив" if той else "рядок змінено" if відкриті else "запису, що відповів, нема"))
        return min(результати, key=lambda р: ДОЛІ.index(р[0]))

    print("Рядки «не виміряно» п'яти оцінок:", len(нв))
    за_класом = collections.defaultdict(collections.Counter)
    for r in нв:
        r["доля"], r["чому"] = доля(r)
        за_класом[r["клас"]][r["доля"]] += 1
    for клас in sorted(за_класом):
        print(f"  клас {клас}: " + ", ".join(f"{д} {н}" for д, н in за_класом[клас].most_common()))
    пф = [r for r in нв if r["клас"] in ("П", "Ф")]
    до = [r for r in пф if r["доля"] == "відсіє до прогону"]
    print(f"Класи П і Ф: {len(пф)}; новий план відсіює до прогону (за текстом, без оцінки): {len(до)}")
    for r in пф:
        if друк_рядків or r["доля"] != "відсіє до прогону":
            print(f"    {r['клас']} {r['оцінка']}:{r['рядок']} #{r['pr']} {r['сцена']} → {r['доля']} ({r['чому'][:110]})")
    # 19 повторних (суворо: PR, сцена, початок питання — як `повтори.py`).
    н = lambda q: re.sub(r"\W+", " ", q.lower())[:45].strip()
    групи = collections.defaultdict(list)
    for r in усі:
        групи[(r["pr"], r["сцена"], н(r["питання"]))].append(r)
    повторні = [к for к, рс in групи.items() if len({r["оцінка"] for r in рс if r["к"] == "нв"}) >= 2]
    за_ключем = {(r["pr"], r["сцена"], н(r["питання"])): r for r in нв}
    долі = collections.Counter()
    print(f"Повторні «не виміряно» (≥2 оцінки): {len(повторні)}")
    for к in повторні:
        r = за_ключем[к]
        долі[r["доля"]] += 1
        print(f"    #{к[0]} {к[1]} → {r['доля']} ({r['чому'][:110]})")
    print("  разом: " + ", ".join(f"{д} {н}" for д, н in долі.most_common()))
    без_долі = [к for к in повторні if за_ключем[к]["доля"] not in ДОЛІ]
    print(f"  повторних без долі (ні в план, ні в bad): {len(без_долі)}")


if __name__ == "__main__":
    main()
