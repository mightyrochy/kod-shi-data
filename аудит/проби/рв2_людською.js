// РВ-2 З-6 (рядок 12 дошки): картка читала опис ДРУГИМ розбирачем. `показ.людською`
// брала СИРИЙ текст моделі й робила JSON.parse після зняття ```; Python
// (`pipeline.опис_відповідь_з_json`) той самий `текст` уже вийняв — толерантно до
// прози довкола JSON і до хвоста після нього. Друкує обидва шляхи поруч: «сам сирий
// текст» (як було, і як лишається для рук 3–4 без каталогу) і «готове поле», яке
// картка подає з 19.09. Запуск: node аудит/проби/рв2_людською.js
const fs = require("fs"), path = require("path");
const html = fs.readFileSync(path.join(__dirname, "..", "..", "джерела", "показ.html"), "utf8");
// Чистка машинних слідів із 20.09.2026 живе окремою функцією (`безМашинногоСліду`):
// на картку прийшов другий текст коду — перелік «код не знає», — і той самий
// останній ярус мусить чистити обидва. Проба виймає її разом із `людською`,
// інакше eval падає з ReferenceError, а не міряє розбір.
const шмат = (від, до) => { const п = html.indexOf(від); const к = html.indexOf(до, п);
  if (п < 0 || к < 0) throw new Error("не знайдено в показ.html: " + від); return html.slice(п, к + до.length); };
// `const` усередині eval лишається в його ж області — назовні воно не видно;
// `var` видно. Тому оголошення міняється на `var` рівно тут, у пробі.
eval(шмат("\nconst безМашинногоСліду = ", "\n    .trim();").replace("const ", "var "));
eval(шмат("\nfunction людською(", "\n}\n"));
const ТЕКСТ = "Блуза й спідниця в одному тоні.", ЯК = ["заправити спереду"];
const тіло = '{"версія":"1","текст":"' + ТЕКСТ + '","як_носити":["' + ЯК[0] + '"]}';
const проби = {
  "чистий JSON":  тіло,
  "JSON у ```":   "```json\n" + тіло + "\n```",
  "проза + JSON": "Ось опис для неї:\n" + тіло,
  "JSON + хвіст": тіло + "\nСподіваюсь, підійде!",
};
// те, що Python віддає полем `опис` на всіх чотирьох випадках — воно однакове
const готове = {текст: ТЕКСТ, як_носити: ЯК};
for (const [н, т] of Object.entries(проби)){
  const [о1, з1] = людською(т);
  const [о2, з2] = людською(т, готове);
  console.log(н.padEnd(13),
              "| сам сирий текст → опис:", JSON.stringify(о1).slice(0, 70), "· задум:", JSON.stringify(з1),
              "|| готове поле → опис:", JSON.stringify(о2).slice(0, 70), "· задум:", JSON.stringify(з2));
}
