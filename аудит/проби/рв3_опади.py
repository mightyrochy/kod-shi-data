"""РВ-3 · «дощ» із чату доїжджає до плитки, а в суд їде «так»: `сценарій.з_показу` кладе
`опади` паспорта («так | ні | невідомо») ПОВЕРХ плитки («дощ | сніг | нема»), і ворота
матеріалу K-WEA-01 / K-WEA-05, які знають лише «дощ / мокрий_сніг / злива», мовчать.
Запуск із теки `джерела`: python3 ../аудит/проби/рв3_опади.py"""
import json
import сценарій as СЦ, bridge as B, outfit as O, суд_образу as С, accessory as A

сц = dict(нагода="побачення", місце="ресторан_районний", година=19, темп_c=12, опади="дощ")   # плитка «дощ»
п = dict(подія="побачення в ресторані", нагода="побачення", опади="так", джерело="модель", вето={})
print("з_показу: плитка опади=%r + паспорт опади=%r → сценарій.опади=%r" % (сц["опади"], п["опади"], СЦ.з_показу(сц, п)[0].get("опади")))
д = B._застосувати_паспорт(dict(сценарій=сц, паспорт=п))
print("_застосувати_паспорт → сценарій.опади=%r · випадок «%s»" % (д["сценарій"].get("опади"), д["випадок"]))

річ = dict(id="в-1", слот="взуття", hex="#553322", назва="Човники замшеві", матеріал="замша",
           волокно="замша", тканина="замша", матеріал_верху="замша", тип="човники")
лік = {}
for опади in ("дощ", "так", "ні"):
    E = O.елементи([річ], стан="надворі")
    for e in E: e.setdefault("волокно", "замша")
    w1 = [z["правило"] for z in С.погода(E, темп_c=12, опади=опади, стан="надворі", речі=[річ]) if z["правило"] == "K-WEA-01"]
    w5 = [z["правило"] for z in A.сезон_і_погода([річ], темп_c=12, опади=опади) if z["правило"] == "K-WEA-05"]
    лік[опади] = (len(w1), len(w5))
    print("опади=%-4r → K-WEA-01 (замша в дощ): %d · K-WEA-05 (матеріал у мокру погоду): %d" % (опади, len(w1), len(w5)))
print("→ «так» = «дощ»: %s · «так» ≠ «ні»: %s"
      % (лік["так"] == лік["дощ"], лік["так"] != лік["ні"]))
