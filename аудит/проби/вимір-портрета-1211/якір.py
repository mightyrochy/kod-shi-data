# ── В. склера проти нейтрального тла ──
def склера(кадр, шкіра):
    """Пікселі склери в смузі ока: обабіч райдужки (|u| 0.45–0.9), не шкіра (ΔE ≥ 8), світліші за шкіру − 10 і менш
    хроматичні за неї; з них — світліша половина. Блиск джерела — межа сенсора."""
    w, h, пкс = ПВ.розпакувати(кадр)
    Cш = cs.lch(шкіра)[1]
    к = []
    for i, p in enumerate(пкс):
        u = abs((i % w + .5 - w / 2) / (w / 2))
        if .45 <= u <= .9 and 6 <= min(p) and max(p) <= 249:
            l = cs.to_lab(p)
            if math.dist(l, шкіра) >= 8 and l[0] > шкіра[0] - 10 and cs.lch(l)[1] < Cш:
                к.append(l)
    if len(к) < 2:
        return []
    м = st.median(l[0] for l in к)
    return [l for l in к if l[0] >= м]


def фон_кріс(lab, білий):
    """lab, нормований так, щоб `білий` став нейтральним своєї яскравості (лінійний RGB, діагональ)."""
    лб = [лін(c) for c in cs.to_rgb(*білий)]
    Y = .2126 * лб[0] + .7152 * лб[1] + .0722 * лб[2]
    лх = [лін(c) * Y / max(1e-6, b) for c, b in zip(cs.to_rgb(*lab), лб)]
    return cs.to_lab([гам(c) * 255 for c in лх])


def склера_за_тлом(img):
    W, H = img.size
    сір = cv2.cvtColor(np.array(img), cv2.COLOR_RGB2GRAY)
    обл = sorted(В.ОБЛ.detectMultiScale(сір, 1.1, 5, minSize=(60, 60)), key=lambda f: -f[2])
    if len(обл) != 1:
        return None
    x, y, w, h = обл[0]
    очі = В.ОКО.detectMultiScale(сір[y:y + h // 2, x:x + w], 1.05, 4, minSize=(w // 9, w // 9))
    очі = sorted(sorted(очі, key=lambda e: -e[2] * e[3])[:2], key=lambda e: e[0])
    if len(очі) != 2 or очі[1][0] < очі[0][0] + очі[0][2] * .6:
        return None
    т = lambda x0, y0, x1, y1: dict(ліво=x0 / W * 1000, верх=y0 / H * 1000, право=x1 / W * 1000, низ=y1 / H * 1000)
    шк = ПВ._зона(ПВ._lab_кадру(В.вирізати(img, т(x + w * .3, y + h * .6, x + w * .7, y + h * .72))), "шкіра")
    if not шк:
        return None
    пкс = []
    for ex, ey, ew, eh in очі:
        cx, cy, r = x + ex + ew / 2, y + ey + eh / 2, ew * .16    # райдужка — як у `вимір.зони`
        пкс += склера(В.вирізати(img, т(cx - 2.6 * r, cy - .6 * r, cx + 2.6 * r, cy + .6 * r)), tuple(шк["lab"]))
    if len(пкс) < 40:    # T3, `лабораторія/зони_з_масок.MIN_SCLERA_PX`
        return None
    кути = []
    for а, б in ((0, 0), (W * .94, 0), (0, H * .94), (W * .94, H * .94)):
        к = np.array(img.crop((int(а), int(б), int(а + W * .06), int(б + H * .06))).resize((12, 12))).reshape(-1, 3)
        labs = [cs.to_lab(tuple(int(v) for v in p)) for p in к]
        m = [st.median(l[i] for l in labs) for i in range(3)]
        if m[0] > 60 and math.hypot(m[1], m[2]) < 8 and st.pstdev(l[0] for l in labs) < 4:
            кути.append(m)
    if not кути:
        return None
    скл = [st.median(l[i] for l in пкс) for i in range(3)]
    тло = [st.median(k[i] for k in кути) for i in range(3)]
    return dict(склера=[round(v, 1) for v in скл], n=len(пкс), тло=[round(v, 1) for v in тло],
                склера_за_тлом=[round(v, 1) for v in фон_кріс(скл, тло)])


def головна():
    опис = json.load(open(sys.argv[1]))
    print("А. Кадри репозиторію, що пройшли ворота (класи; сивина за зсувом балансу):")
    підс = []
    for л, фото in опис.items():
        for ф in фото:
            img = Image.open(ф["шлях"]).convert("RGB")
            з, _ = В.зони(img)
            if not з:
                continue
            кадри = {ім: В.вирізати(img, р) for ім, р in з.items()}
            r = звести(ф["файл"], {з_: {ім: зсунути(к, м) for ім, к in кадри.items()} for з_, м in ЗСУВИ.items()})
            if r:
                підс.append(r)
    print("  кадрів у воротах %d; розбіжних тверджень між зсувами %d; змін класу сивини %d; сивина певна %d" % (
        len(підс), sum(r["розбіжних"] for r in підс), sum(r["змін_сивини"] for r in підс), sum(r["сива_певна"] for r in підс)))
    print("Б. Синтетичні портрети (сивина за зсувом балансу):")
    синт = {}
    for ім, (ш, в, о) in ЛЮДИ.items():
        к = портрет(ш, в, о)
        синт[ім] = звести(ім, {з: {і: зсунути(кк, м) for і, кк in к.items()} for з, м in ЗСУВИ.items()})
    print("  розбіжних тверджень %d; змін класу сивини %d; чорне певне «не сиве» %d з 2; сиве певне %d з 4" % (
        sum(r["розбіжних"] for r in синт.values()), sum(r["змін_сивини"] for r in синт.values()),
        sum(1 for ім, r in синт.items() if ім.startswith("чорне") and isinstance(r["сивина"], dict) and not r["сивина"]["волосся"]),
        sum(1 for ім, r in синт.items() if "сиве" in ім and r["сива_певна"])))
    print("В. Склера кадрів репозиторію за нейтральним тлом студії:")
    скл = []
    for л, фото in опис.items():
        for ф in фото:
            r = склера_за_тлом(Image.open(ф["шлях"]).convert("RGB"))
            if r:
                скл.append(r)
                print("  %-40s склера %s (n %d), тло %s → склера за тлом %s" % (ф["файл"], r["склера"], r["n"], r["тло"], r["склера_за_тлом"]))
    if скл:
        a = [r["склера_за_тлом"][1] for r in скл]; b = [r["склера_за_тлом"][2] for r in скл]
        C = [math.hypot(x, y) for x, y in zip(a, b)]
        print("  кадрів %d; a* медіана %.1f (%.1f…%.1f), b* медіана %.1f (%.1f…%.1f), C* %.1f…%.1f" % (
            len(скл), st.median(a), min(a), max(a), st.median(b), min(b), max(b), min(C), max(C)))


if __name__ == "__main__":
    головна()
