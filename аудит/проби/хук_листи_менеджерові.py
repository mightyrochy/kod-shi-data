#!/usr/bin/env python3
"""Проба хука `.claude/хуки/листи_менеджерові.py` (наряд хук-листи-менеджерові): вхід хука з файлу → рішення.

Запуск: python3 аудит/проби/хук_листи_менеджерові.py [шлях_до_хука]   (без аргументу — хук з робочого дерева).
ДО: хука на `main` нема — кожен лист пропускався. Мірило: «Стан …» менеджерові — відмова; «РІШЕННЯ ПОТРІБНЕ: …» —
пропущено; два «ЗВЕДЕННЯ» з різницею 1 год — друге відмова, через 6 год — пропущено; лист іншій сесії — пропущено;
відправник, що не диспетчер, — пропущено; зіпсований СТАН — пропуск з попередженням.
"""
import json
import os
import subprocess
import sys
import tempfile

КОРІНЬ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
ХУК = sys.argv[1] if len(sys.argv) > 1 else os.path.join(КОРІНЬ, ".claude", "хуки", "листи_менеджерові.py")
МЕНЕДЖЕР, ДИСПЕТЧЕР = "session_MGR1", "session_DSP1"
СТАН = (f"| роль | сесія |\n|---|---|\n| диспетчер | {ДИСПЕТЧЕР} (ДИСПЕТЧЕР-12) | x |\n"
        f"| менеджер | {МЕНЕДЖЕР} (передача) | x |\n")


def запуск(кому, текст, коли, стан_файл, я=ДИСПЕТЧЕР, стан=СТАН):
    with tempfile.TemporaryDirectory() as т:
        os.makedirs(os.path.join(т, "аудит"))
        with open(os.path.join(т, "аудит", "СТАН.md"), "w", encoding="utf-8") as ф:
            ф.write(стан)
        вхід = {"tool_name": "mcp__claude-code-remote__send_message",
                "tool_input": {"session_id": кому, "message": текст}}
        env = dict(os.environ, CLAUDE_PROJECT_DIR=т, ЛИСТИ_СТАН_ФАЙЛ=стан_файл, ЛИСТИ_ЗАРАЗ=коли,
                   CLAUDE_CODE_REMOTE_SDK_URL=f"https://x/sessions/cse_{я[len('session_'):]}")
        р = subprocess.run([sys.executable, ХУК], input=json.dumps(вхід), capture_output=True, text=True, env=env)
    return ("відмова" if "deny" in р.stdout else "пропущено") + (" +stderr" if р.stderr.strip() else "")


def main():
    with tempfile.TemporaryDirectory() as т:
        ф = os.path.join(т, "зведення")
        випадки = [
            ("Стан: усе гаразд", МЕНЕДЖЕР, "2026-10-29T10:00:00", ДИСПЕТЧЕР, СТАН, "відмова"),
            ("РІШЕННЯ ПОТРІБНЕ: чи лишати п.5", МЕНЕДЖЕР, "2026-10-29T10:00:00", ДИСПЕТЧЕР, СТАН, "пропущено"),
            ("ЗВЕДЕННЯ 10:00 UTC", МЕНЕДЖЕР, "2026-10-29T10:00:00", ДИСПЕТЧЕР, СТАН, "пропущено"),
            ("ЗВЕДЕННЯ 11:00 UTC", МЕНЕДЖЕР, "2026-10-29T11:00:00", ДИСПЕТЧЕР, СТАН, "відмова"),
            ("ЗВЕДЕННЯ 16:01 UTC", МЕНЕДЖЕР, "2026-10-29T16:01:00", ДИСПЕТЧЕР, СТАН, "пропущено"),
            ("Стан: щось", "session_ІНША", "2026-10-29T10:00:00", ДИСПЕТЧЕР, СТАН, "пропущено"),
            ("Стан: від виконавця", МЕНЕДЖЕР, "2026-10-29T10:00:00", "session_EXE1", СТАН, "пропущено"),
            ("Стан: СТАН без рядка менеджера", МЕНЕДЖЕР, "2026-10-29T10:00:00", ДИСПЕТЧЕР, "нічого", "пропущено"),
        ]
        збої = 0
        for текст, кому, коли, я, стан, чекано in випадки:
            факт = запуск(кому, текст, коли, ф, я, стан)
            збої += not факт.startswith(чекано)
            print(f"{'ок ' if факт.startswith(чекано) else 'ЗБІЙ'} {текст!r} → {факт} (чекано {чекано})")
        print("збоїв:", збої)
        sys.exit(1 if збої else 0)


main()
