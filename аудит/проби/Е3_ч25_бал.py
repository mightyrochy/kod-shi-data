# -*- coding: utf-8 -*-
"""Е3-одна-величина ч25 (п.6(а)): ДО → ПІСЛЯ — бал комбінації кроїв (`hypergraph`) і поріг краю взуття (`поломки`).

Запуск із кореня репозиторію:
    python3 аудит/проби/Е3_ч25_бал.py                          # ПІСЛЯ: код цієї гілки
    git worktree add /tmp/до <SHA_ДО>
    python3 аудит/проби/Е3_ч25_бал.py --код /tmp/до/джерела    # ДО: той самий скрипт на старому коді
    python3 аудит/проби/Е3_ч25_бал.py --похибка-см 0.5         # ПІСЛЯ з ВИГАДАНИМ джерелом похибки ширин (лише
                                                               # доказ, що рішення йде понад похибку, не вимір)

Каталог не потрібен: бал рахується на тілі й крої-шаблонах (`силует_крої`), модель і платні API не кличуться.
Друкує на чотирьох тілах (пісочний, яблуко, трикутник, груша):
  1. `простір` сіткою «крої» (шлях брифа) і «повна»: оцінено, живих (не доведено нульових), доведено живих,
     невідомих, доведених нулів, частка вище 0.80, ярус кроїв і довжин;
  2. ребра `крій_*`, що їдуть у бриф: сила й початок рядка; число рішень «невідомо»;
  3. `крої_для_пулу`: слоти з ярусом (порожній — ранг пулу нейтральний);
  4. `поломки._краї_навпаки`: хибні знахідки взуття на краї від 0 до 45 см з кроком 0.1."""
import sys, pathlib, os, io, contextlib, collections

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
код = pathlib.Path(sys.argv[sys.argv.index("--код") + 1]).resolve() if "--код" in sys.argv else КОРІНЬ / "джерела"
os.chdir(код); sys.path.insert(0, str(код))
import fit as ПС, hypergraph as ГГ, поломки as П

if "--похибка-см" in sys.argv:       # лише доказ: джерело похибки ширини (там, де його нема) — задане число
    import силует_лінії as _СЛ
    _п = float(sys.argv[sys.argv.index("--похибка-см") + 1])
    _СЛ.похибка_ширини = lambda з: _п
    print(f"ВИГАДАНЕ джерело похибки ширини: {_п} см на кожному рівні (не вимір)")
print(f"код: {код}")

ТІЛА = [(п, ПС.тіло(зр, обх)) for п, зр, обх in (
    ("пісочний", 168, dict(плечі=98, груди=92, талія=72, стегна=100)),
    ("яблуко", 160, dict(плечі=104, груди=104, талія=88, стегна=112)),
    ("трикутник", 170, dict(плечі=100, груди=96, талія=84, стегна=104)),
    ("груша", 156, dict(плечі=88, груди=98, талія=80, стегна=94)))]

print("\n1. ПРОСТІР: сітка «крої» (шлях брифа) і «повна»")
решітки = {}
for п, T in ТІЛА:
    for сітка in ("крої", "повна"):
        пр = ГГ.простір(T, сітка=сітка)
        решітки[(п, сітка)] = пр
        р = пр["роздільність"]
        ярус = пр.get("крої_ярус")
        print(f"   {п:10s} {сітка:6s} оцінено {пр['оцінено']:4d} живих {пр['живих']:4d} "
              f"доведено_живих {пр.get('доведено_живих', '—')!s:>4} "
              f"невідомих {пр.get('невідомих', '—')!s:>4} нулів {пр['нульових']:3d} "
              f"(блокер {пр['нуль_розкладка'].get('блокер')}, влучання=0 {пр['нуль_розкладка'].get('влучання=0')}) "
              f"вище_0.8 {р['частка_вище_08']} [{р.get('частка_вище_08_від', '—')}…{р.get('частка_вище_08_до', '—')}] "
              f"кращий {пр['кращий_бал']}")
        if сітка == "крої":
            print(f"              ярус кроїв: {ярус if ярус is not None else '(ДО: за розривом 0.03 — див. ребра)'} "
                  f"· довжини верх {пр['довжини']['верх']} низ {пр['довжини']['низ']}"
                  f"{'' if пр.get('довжини_названо', True) else ' (не названо)'}")

print("\n2. РЕБРА крій_* ДО БРИФА")
невідомо = названо = 0
for п, T in ТІЛА:
    пр = решітки[(п, "крої")]
    for р in ГГ.ребра(T, пр):
        if р["ід"].startswith("крій_"):
            ясно = р["сила"] != "питання"
            названо += ясно; невідомо += not ясно
            print(f"   {п:10s} {р['ід']:9s} сила {р['сила']:8s} заява {'є' if р.get('заява') else 'нема'} {р['рядок'][:96]}")
print(f"   → рішень «ярус кроїв названо» {названо}, «невідомо/жодного» {невідомо}")

print("\n3. КРОЇ ДЛЯ ПУЛУ (ярус; порожній слот — ранг пулу нейтральний)")
for п, T in ТІЛА:
    кп = ГГ.крої_для_пулу(T) or {}
    print(f"   {п:10s} " + ("; ".join(f"{с}: {sorted(кп[с]['ярус'])}" for с in кп) or "жодного слота — нейтрально"))

print("\n4. ПОЛОМКИ: від якого краю верху взуття `_краї_навпаки` дійшла до порівняння з опуклістю (край 0…45 см, крок 0.1)")
T = ТІЛА[0][1]
дійшли = []
_справжня = П._ФІТ.край_проти_локального
def _лічильник(проф, край_см, *а, **к):
    дійшли.append(round(край_см, 1))
    return _справжня(проф, край_см, *а, **к)
П._ФІТ.край_проти_локального = _лічильник
for i in range(0, 451):
    П._краї_навпаки([], T["профіль"], [dict(id="в", слот="взуття", крій="boot", верх_см=i / 10, низ_см=0.0)])
П._ФІТ.край_проти_локального = _справжня
print(f"   перше значення краю, що судиться: {min(дійшли) if дійшли else None} см; судиться {len(дійшли)} з 451 "
      f"(ДО: поріг 1.0 см без джерела; ПІСЛЯ: понад допуск виробу `fit.ДОПУСК_ВИРОБУ_СМ`)")
