"""Зведення збурення: для кожного рядка — скільки виконань і чи різняться відбитки з її hex як є (в0) і зсунутим (в1).
так — відбитки різні (її hex доходить); ні — виконується з однаковими; — — не виконується.
Запуск: python3 зведення.py в0.json в1.json  (виводи `збурення.py` з `річ-ознаки-прилад-поріг-0711`, аргумент 0 і 1)"""
import json, sys
в0, в1 = (json.load(open(п, encoding="utf8")) for п in sys.argv[1:3])
for р in sorted(в0):
    а, б = в0[р], в1.get(р, [])
    print("%s · %d · %s" % (р, len(а), "—" if not а and not б else "так" if а != б else "ні"))
