# Н-outfit-2-096: кожен ключ ПОРЯДОК_ТІЛА має виробника, і кожен слот виробника,
# який лежить на тілі, є в ПОРЯДОК_ТІЛА. До правки «прикраси» не було (40 речей
# каталогу стенда повз K-MAT-04-A), а «годинник» стояв без жодного виробника.
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "джерела"))
import feed, bridge, outfit as O

# composer ставить ці слоти сам — у фіді їх нема й не має бути (composer.py:69,82)
ВІД_КОМПОЗИТОРА = {"комплект", "колготи", "шкарпетки"}
виробники = (set(feed.ІМЕНА_СЛОТІВ) | {п for п, _ in feed.ПІД_СЛОТИ_ПРИКРАС}
             | set(bridge.УСІ_СЛОТИ) | ВІД_КОМПОЗИТОРА)
без_виробника = sorted(set(O.ПОРЯДОК_ТІЛА) - виробники)

ш = feed.каталог_на_диску("каталог_brief.xml")
к = feed.читати_yml(ш); к = к[0] if isinstance(к, tuple) else к
живі = {feed.слот(o) for o in к} - {None}
поза = sorted(живі - set(O.ПОРЯДОК_ТІЛА))

збої = 0
for мітка, факт in (("ключі ПОРЯДОК_ТІЛА, яких не виробляє ніхто", без_виробника),
                    ("слоти каталогу поза ПОРЯДОК_ТІЛА", поза)):
    збої += bool(факт)
    print("%s %-42s %s" % ("✓" if not факт else "✗", мітка, факт or "—"))
print("ВПАЛО %d" % збої)
sys.exit(1 if збої else 0)
