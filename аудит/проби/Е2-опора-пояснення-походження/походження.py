"""Факти дня в «day» опису через шлях продукту, ДО → ПІСЛЯ (наряд Е2-опора-пояснення-походження; дошка 16228, 16229).

Вхід — те, що показ віддав мосту в записаних прогонах: `вхід_прогону.сценарій` і `паспорт` кожного прогону з файла
вердиктів (нічний 15.11 — `вердикти.txt` сцен; «як людина» 4 — `verdykty-*.json` с5 і с8). Шлях — той самий, яким опис
складає продукт: `міст_вхід.застосувати_паспорт` → `міст_опис.день_опису` (на дереві без неї — ті самі два рядки, що в
`міст_опис.опис` бази: `з_показу` і `день_кодами(сцен, паспорт or {})`) → `розбір_відповідей.опис_обʼєкт` →
`дріт_моделі.опис` → поле «day». Двічі: з паспортом і без нього (`паспорт` знято — шлях, коли показ паспорта не дав).
Кожен факт «day» — з походженням (`provenance`) і фактом картки паспорта: «її слова без уривка» — факт з позначкою
her_words, у картки якого нема ні уривка її слів, ні дотику її руки. Повтор входу, не відповідей.
Запуск з кореня: python3 аудит/проби/Е2-опора-пояснення-походження/походження.py [--дерево <тека з джерела/>]"""
import collections, glob, json, os, sys, warnings

warnings.simplefilter("ignore")
КОРІНЬ = os.getcwd()
ДЕРЕВО = sys.argv[sys.argv.index("--дерево") + 1] if "--дерево" in sys.argv else КОРІНЬ
sys.path.insert(0, os.path.join(ДЕРЕВО, "джерела"))
os.chdir(os.path.join(ДЕРЕВО, "джерела"))
import міст_вхід as МВ, міст_опис as МО, розбір_відповідей as РВ, дріт_моделі as Д, сценарій as СЦ, паспорт_нагоди as ПН
from сценарій import _ПОЛЕ_КЛЮЧА_ДНЯ as ПОЛЕ
os.chdir(КОРІНЬ)


def день_опису(d):
    if hasattr(МО, "день_опису"):
        return МО.день_опису(d)[1]
    сцен = ПН.з_показу(d.get("сценарій"), d.get("паспорт"))[0]                 # `міст_опис.опис` бази, рядки 705, 761
    пасп = d.get("паспорт") if isinstance(d.get("паспорт"), dict) else None
    return СЦ.день_кодами(сцен, пасп or {}) or None


def прогони():
    файли = [("н", ф) for ф in sorted(glob.glob("аудит/проби/Е1-нічний-живий-20261115/*/вердикти.txt"))] + \
            [("4", ф) for ф in sorted(glob.glob("аудит/проби/живий-як-людина-4/с[58]_*/verdykty-*.json"))]
    for набір, ф in файли:
        в = json.load(open(ф, encoding="utf8"))
        for і, пр in enumerate(в.get("прогони") or [], 1):
            с = dict(в.get("спільне") or {}, **(пр.get("спільне") or {}))
            вх = с.get("вхід_прогону") or {}
            if isinstance(вх.get("сценарій"), dict) and isinstance(с.get("паспорт"), dict):
                yield набір, ф.split("/")[-2], і, вх["сценарій"], с["паспорт"]


def факт_картки(пасп, сцен, ключ):
    поле = ПОЛЕ.get(ключ)
    return ((пасп or {}).get("картка_запиту") or {}).get(поле) or (сцен.get("картка_запиту") or {}).get(поле) or {}


л, ключі = collections.Counter(), collections.Counter()
рядки = []
for набір, сцена, і, сцен, пасп in прогони():
    for шлях, d in (("з паспортом", dict(сценарій=сцен, паспорт=пасп)), ("без паспорта", dict(сценарій=сцен))):
        d = МВ.застосувати_паспорт(json.loads(json.dumps(d)))
        день = день_опису(d) or {}
        звідки = день.get("provenance") or {}
        дріт = Д.опис(РВ.опис_обʼєкт([], день=день)).get("day") or {}
        її = [к for к in дріт if звідки.get(к) == "her_words"]
        без = [к for к in її if not (str(факт_картки(пасп, сцен, к).get("уривок") or "").strip()
                                      or факт_картки(пасп, сцен, к).get("джерело") == "hand")]
        # запис походження, який мав код дерева: паспорт; без паспорта — картка сценарію (ПІСЛЯ) чи нічого (ДО)
        запис = пасп if шлях == "з паспортом" else (
            {"картка_запиту": сцен.get("картка_запиту") or {}} if hasattr(МО, "день_опису") else {})
        без_запису = [к for к in її if not ((запис.get("картка_запиту") or {}).get(ПОЛЕ.get(к))
                                             or ПОЛЕ.get(к) in (запис.get("джерело_полів") or {}))]
        л["%s · her_words без запису походження у вході" % шлях] += len(без_запису)
        л["%s · фактів «day»" % шлях] += len(дріт)
        л["%s · з позначкою her_words" % шлях] += len(її)
        л["%s · her_words без уривка й дотику" % шлях] += len(без)
        л["%s · her_words з її уривком" % шлях] += sum(1 for к in її if str(факт_картки(пасп, сцен, к).get("уривок") or "").strip())
        for к in без:
            ключі["%s: %s" % (шлях, к)] += 1
        рядки.append("%s %-30s прогін %d | %-12s | day: %s | без уривка: %s" % (
            набір, сцена, і, шлях, ",".join("%s(%s)" % (к, звідки.get(к, "?")) for к in дріт) or "—", ",".join(без) or "—"))
    л["прогонів"] += 1
print("\n".join(рядки))
print()
for к, v in sorted(л.items()):
    print("%-50s %d" % (к, v))
print("her_words без уривка — ключі:", ", ".join("%s ×%d" % кв for кв in ключі.most_common()) or "—")

