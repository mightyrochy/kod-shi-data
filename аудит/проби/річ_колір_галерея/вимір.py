"""ДО/ПІСЛЯ кореня та всіх наявних кадрів галереї; без мережі й моделей."""
import collections
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import types

КОРІНЬ = Path(__file__).resolve().parents[3]
ВИХІД = Path(__file__).resolve().parent
БАЗА = "dc451033e51070d44ea809c9123755f3933b752b"
МОДУЛІ = ("жнива_кадри", "фід_кадр_колір", "кадри_групи")
sys.path.insert(0, str(КОРІНЬ / "джерела"))


def старий_код(ім):
    """Текст модуля з базового коміту, без перемикання робочої гілки."""
    return subprocess.check_output(["git", "show", f"{БАЗА}:джерела/{ім}.py"],
                                   cwd=КОРІНЬ).decode("utf-8")


def старий_модуль(ім):
    """Незмінений модуль ДО в пам'яті для того самого набору даних."""
    мод = types.ModuleType("до_" + ім)
    мод.__file__ = str(КОРІНЬ / "джерела" / (ім + ".py"))
    exec(compile(старий_код(ім), мод.__file__, "exec"), мод.__dict__)
    return мод


def прилад():
    """Прилад кореня на повному обсязі Python/JS, базовому й робочому деревах."""
    шлях = КОРІНЬ / "джерела" / "прилади" / "корінь_річ_колір_вимір.py"
    with tempfile.TemporaryDirectory() as тека:
        до = Path(тека)
        (до / "джерела" / "показ").mkdir(parents=True)
        for джерело in (КОРІНЬ / "джерела").glob("*.py"):
            shutil.copyfile(джерело, до / "джерела" / джерело.name)
        for джерело in (КОРІНЬ / "джерела" / "показ").glob("*.js"):
            shutil.copyfile(джерело, до / "джерела" / "показ" / джерело.name)
        for ім in МОДУЛІ:
            (до / "джерела" / (ім + ".py")).write_text(старий_код(ім), encoding="utf-8")
        for назва, дерево in (("ДО", до), ("ПІСЛЯ", КОРІНЬ)):
            вихід = subprocess.check_output([sys.executable, "-W", "ignore", str(шлях),
                                             "--корінь", str(дерево)], cwd=КОРІНЬ)
            (ВИХІД / (назва + ".txt")).write_bytes(вихід)
            print(назва, вихід.decode("utf-8").splitlines()[-1], flush=True)


def каталог():
    """Усі наявні галереї, черга та рішення про спір на повному каталозі."""
    import feed as Ф
    import фід_збагачення as З
    import фід_кадр_колір as К
    import кадри_групи as Г
    import жнива_кадри as Ж
    import чистка_каталогу as Ч
    os.chdir(КОРІНЬ / "джерела")
    Ч.забезпечити_чистим("каталог_повний.xml")
    offers = Ф.читати_yml(Ф.каталог_на_диску("каталог_повний.xml"))[0]
    зб, кадри = Ф.читати_збагачення(), К.читати_кадри()
    до_К, до_Г, до_Ж = (старий_модуль(ім) for ім in ("фід_кадр_колір", "кадри_групи", "жнива_кадри"))
    л = collections.Counter(варіантів=len(offers), галерей=len(кадри))
    зміни = []
    for ід, записи in кадри.items():
        л["кадрів"] += len(записи)
        for в in записи:
            л["старий_lab"] += bool(в.get("lab"))
            л["придатних_із_розкидом"] += bool(К.вимір_кадру(в))
            for назва, мод in (("до", до_Ж), ("після", Ж)):
                причина = мод.чому_мірити(в, в.get("url") or "", 2)
                if причина:
                    л["черга_" + назва + "_" + причина] += 1
        for назва, мод in (("до", до_Г), ("після", Г)):
            групи = мод.групи_кадрів(зб.get(ід), записи)
            for поле in ("групи", "без_виміру", "для_картки", "службові"):
                л[поле + "_" + назва] += len(групи[поле])
    for o in offers:
        з = зб.get(o["id"])
        if not З.збагачення_придатне(з):
            continue
        спір = З.колір_спір(з, o)
        if not спір:
            continue
        л["спорів"] += 1
        до = до_К.після_спору(o, з, спір, dict(кадри=кадри))
        після = К.після_спору(o, з, спір, dict(кадри=кадри))
        if до != після:
            зміни.append(dict(id=o["id"], до=до, після=після))
        for назва, р in (("до", до), ("після", після)):
            л["фото_переважило_" + назва] += bool(р["позначка"])
    результат = dict(база=БАЗА, числа=dict(л), зміни_спору=зміни,
                     межа="Наявний каталог, без нового ATR/SAM; власність кадру не перевіряється цим кроком")
    (ВИХІД / "каталог.json").write_text(json.dumps(результат, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(результат["числа"], ensure_ascii=False), flush=True)
    print("змінених рішень спору:", len(зміни), flush=True)


if __name__ == "__main__":
    прилад()
    каталог()
