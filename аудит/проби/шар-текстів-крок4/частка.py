"""Лічить речення невизначеності в записі перекладу Н2 або в полях показу картки."""
import argparse
import gzip
import json
from pathlib import Path
import re


МЕЖА = re.compile(r'(?<=[.!?…])\s+|\n+')
НЕВИЗНАЧЕНІСТЬ = re.compile(
    r"\b(?:не (?:знаю|відомо|стверджую|обіцяю|гарантую|ручаюся|оцінюю|беруся (?:казати|стверджувати)"
    r"|маю (?:даних|інформації|підстав))"
    r"|не (?:можу|вдалося|вдалось) (?:\w+ )?(?:сказати|стверджувати|підтвердити|перевірити|гарантувати|обіцяти)"
    r"|(?:сказати|стверджувати|підтвердити|перевірити|гарантувати|обіцяти) не можу"
    r"|немає (?:даних|інформації)|не підтверджен\w*|не зазначен\w*|невідом\w*)\b", re.I)
ПЕРЕКЛАД = "Ти — перекладачка в застосунку-стилістці. Ти пишеш природною українською тексти"


def н2(файл):
    """Бере переклад опису й порад з останнього виклику текстів картки."""
    зчитати = gzip.open if файл.suffix == ".gz" else open
    with зчитати(файл, "rt", encoding="utf-8") as потік:
        записи = [json.loads(р) for р in потік if р.strip()]
    виклик, = [р for р in записи if str(р["запит"]).startswith(ПЕРЕКЛАД)]
    return list(json.loads(виклик["відповідь"]).values())


def показ(файл):
    """Бере лише основний опис і поради, які малює показ."""
    картки = json.loads(файл.read_text(encoding="utf-8"))["картки"]
    return [т for к in картки if not к.get("збій") for т in [к.get("опис") or "", *(к.get("як_носити") or [])]]


def головна():
    аргументи = argparse.ArgumentParser(description=__doc__)
    аргументи.add_argument("--показ", action="store_true")
    аргументи.add_argument("файли", nargs="+", type=Path)
    вхід = аргументи.parse_args()
    чисельник, знаменник = 0, 0
    for файл in вхід.файли:
        речення = [р.strip() for т in (показ if вхід.показ else н2)(файл) for р in МЕЖА.split(т) if р.strip()]
        невідоме = [р for р in речення if НЕВИЗНАЧЕНІСТЬ.search(р)]
        if not речення:
            raise SystemExit(f"{файл}: немає основного тексту картки")
        print(f"{файл}: {len(невідоме)}/{len(речення)} ({len(невідоме) / len(речення):.1%})")
        for р in невідоме:
            print(f"  {р}")
        чисельник += len(невідоме)
        знаменник += len(речення)
    print(f"Разом {чисельник}/{знаменник} ({чисельник / знаменник:.1%})")


if __name__ == "__main__":
    головна()
