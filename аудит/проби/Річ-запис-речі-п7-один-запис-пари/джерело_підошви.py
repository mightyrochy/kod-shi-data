"""Доробка #4162 (дошка 16317): чи несе підошва пари справжнє джерело. Та сама вибірка, що в скрипті автоперевірки
(`аудит/перевірки/автоперевірка-4162-3fecf881…/джерело_підошви.py`): пара з основою підошви без кодів картки, чий
параметр картки підошви не називає, — значення з тексту назви чи опису. Лічить, скільки з них `пара_взуття.підошва`
називає КАРТКОЮ (мало бути 0), і розподіл джерел підошви на всіх парах.

    python3 -W ignore аудит/проби/Річ-запис-речі-п7-один-запис-пари/джерело_підошви.py [кеш.pkl]

Кеш — той, що будує `лічба_після.py` (повний каталог)."""
import collections, json, os, pathlib, pickle, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[3] / "джерела"))
import фід_взуття as Ф
import пара_взуття as П

кеш = sys.argv[1] if len(sys.argv) > 1 else os.path.join("/tmp", "лічба_після_кеш.pkl")
каталог, офери = pickle.loads(pathlib.Path(кеш).read_bytes())
сирі = {о["id"]: о for о in офери}
пари = [р for р in каталог if р.get("слот") == "взуття"]
з_тексту, карткою = [], []
for р in пари:
    if not р.get("підошва") or р.get("підошва_коди"):
        continue
    о = сирі[р["id"]]
    if Ф.підошва_картки(о.get("параметри"), ""):
        continue
    з_тексту.append(р["id"])
    if П.підошва(р)[1] == П.КАРТКА:
        карткою.append(р["id"])
джерела = collections.Counter(str(П.підошва(р)[1]) for р in пари)
print(json.dumps(dict(пар=len(пари), підошва_з_тексту=len(з_тексту), текст_названо_карткою=len(карткою),
                      приклади_з_тексту=з_тексту[:3], джерела_підошви=dict(джерела.most_common())),
                 ensure_ascii=False, indent=1))
assert not карткою, карткою
