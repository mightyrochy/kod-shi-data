def шлях(u): return '/tmp/фото_метал/' + hashlib.md5(u.encode()).hexdigest() + '.img'
def тягти(u):
    p = шлях(u)
    if not os.path.exists(p) or os.path.getsize(p) == 0:
        subprocess.run(['curl', '-sS', '-L', '-m', '40', '-o', p, u], capture_output=True)
    return p
