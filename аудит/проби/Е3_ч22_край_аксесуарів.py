# -*- coding: utf-8 -*-
"""Е3-одна-величина ч22 (п.6, рішення 07.11): ДО → ПІСЛЯ — K-EDG-01 (`аксесуари_край.край_аксесуара`) і
K-SHO-05/K-SHO-11 (`аксесуари_взуття.халява_і_поділ`): край проти локального максимуму понад похибку.

Запуск із кореня репозиторію:
    python3 аудит/проби/Е3_ч22_край_аксесуарів.py                        # ПІСЛЯ: код цієї гілки
    git worktree add /tmp/до <SHA_ДО>
    python3 аудит/проби/Е3_ч22_край_аксесуарів.py --код /tmp/до/джерела   # ДО: той самий скрипт на старому коді

Каталог — `джерела/каталог_повний.xml` цього клону (один для ДО й ПІСЛЯ); модель і платні API не кличуться.
Кожна річ каталогу, чий слот має край (сумка з `ремінь_см`, рукавички з `край_руки_см`, взуття з халявою, низ/сукня
з довжиною), проганяється поодинці на шести тілах. Друкує лічбу за правилом і силою: `soft` — край судиться
(доведений понад похибку), `утримано` — правило каже, що не судить, мовчання — «без знахідки» (край не на опуклості
чи речі нема входу)."""
import sys, pathlib, json, collections, os, io, contextlib

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
код = pathlib.Path(sys.argv[sys.argv.index("--код") + 1]).resolve() if "--код" in sys.argv else КОРІНЬ / "джерела"
os.chdir(код); sys.path.insert(0, str(код))
import feed as Ф, bridge as B, composer as КМ, fit as ПС
import аксесуари_край as АК, аксесуари_взуття as АВ

print(f"код: {код}")
вх = json.load(open(код / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску(str(КОРІНЬ / "джерела" / "каталог_повний.xml")); вх["гілка"] = 0
with contextlib.redirect_stdout(io.StringIO()):
    json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
_F, T_стенд, _зр, _kw = B._збірка(вх)
ТІЛА = [("стенд", T_стенд)] + [(п, ПС.тіло(зр, обх)) for п, зр, обх in (
    ("пісочний", 168, dict(плечі=98, груди=92, талія=72, стегна=100)),
    ("яблуко", 160, dict(плечі=104, груди=104, талія=88, стегна=112)),
    ("трикутник", 170, dict(плечі=100, груди=96, талія=84, стегна=104)),
    # литка виміряна й ширша за коліно: на нозі є локальний максимум, і халява та поділ доходять до читача
    ("литка виміряна", 168, dict(плечі=98, груди=92, талія=72, стегна=100, коліно=36, литка=40)),
    ("литка 2", 160, dict(плечі=104, груди=104, талія=88, стегна=112, коліно=34, литка=38)))]
СЛОТИ = {"сумка", "рукавички", "взуття", "низ", "сукня", "комплект", "верхній_шар"}
речі = [(c, c.get("слот")) for c in кат if c.get("слот") in СЛОТИ]
print(f"каталог: {len(кат)} речей, з краєм-кандидатом за слотом: {len(речі)}")

# Стан відповіді читача на кожному краї: judged — обидві True (край судиться); спростовано — котрась False (доведено
# «ні»: мовчання правдиве); невідомо — жодної False, хоч одна None (на цьому читач мовчав до ч22).
стан = collections.Counter()
_оригінал = ПС.край_проти_локального
def _лічильник(*a, **kw):
    м = _оригінал(*a, **kw)
    if sys._getframe(1).f_code.co_name in ("край_аксесуара", "халява_і_поділ"):
        в = (м["на_максимумі"], м["важіль_є"])
        стан["судиться" if all(x is True for x in в) else "спростовано" if False in в else "невідомо"] += 1
    return м
ПС.край_проти_локального = _лічильник

підсумок = collections.Counter()
for п, T in ТІЛА:
    лічба = collections.Counter()
    for c, сл in речі:
        р = КМ.у_річ(dict(c), сл, T)
        for f, назва in ((АК.край_аксесуара, "K-EDG-01"), (АВ.халява_і_поділ, "K-SHO")):
            if назва == "K-EDG-01" and сл not in ("сумка", "рукавички"): continue
            if назва == "K-SHO" and сл not in ("взуття", "низ", "сукня", "комплект", "верхній_шар"): continue
            з = [x for x in f(T, [р]) if x["правило"] in ("K-EDG-01", "K-SHO-05", "K-SHO-11")
                 and x["сила"] in ("soft", "утримано")]
            # «утримано» K-EDG-01 про край поза профілем — інший код, не цей клас
            for x in з:
                коди = tuple(sorted(a.get("code") for a in (x.get("заяви") or ())))
                if x["сила"] == "утримано" and коди != ("edge_not_judged_error_unknown",):
                    continue
                лічба[(x["правило"], x["сила"])] += 1
    for k, v in лічба.items(): підсумок[k] += v
    print(f"   {п:10s} {dict(sorted(лічба.items()))}")
print("   разом     ", dict(sorted(підсумок.items())))
print("   краї, що дійшли до читача (усі тіла):", dict(sorted(стан.items())))
