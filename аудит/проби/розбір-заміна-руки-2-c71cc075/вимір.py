"""Лічить весь запис сцени з незмінного коміту; не звертається до моделі чи мережі."""
import hashlib
import json
from pathlib import Path
import subprocess

КОРІНЬ = Path(__file__).resolve().parents[3]
ЗАПИС = "6c44a6c5edac74caeb499ebee919bc71a763d181"
КОД = "c71cc075fdaca37a3df5b1419fc035acd0035024"
СЦЕНА = "аудит/проби/автоживий-" + КОД + "/ж4_робота_стримано/"


def git(*аргументи):
    """Читає байти об'єкта без checkout і зміни робочого дерева."""
    return subprocess.check_output(["git", *аргументи], cwd=КОРІНЬ)


def обєкт(шлях):
    """Читає JSON із коміту запису."""
    return json.loads(git("show", ЗАПИС + ":" + СЦЕНА + шлях))


def вимір():
    """Повертає факти всіх обмінів сцени та межі їхньої доказовості."""
    файли = git("ls-tree", "-r", "--name-only", ЗАПИС, "--", СЦЕНА).decode().splitlines()
    імена = [ім[len(СЦЕНА):] for ім in файли]
    обміни = [(ім, обєкт(ім)) for ім in імена if ім.startswith("VIDPOVIDI/обмін/")]
    заміни = []
    for ім, обмін in обміни:
        текст = "\n".join(б.get("text", "") for б in обмін["запит"]["messages"][-1]["content"])
        try:
            запит = json.loads(текст)
        except ValueError:
            continue
        if isinstance(запит, dict) and "replacement" in запит:
            відповідь = json.loads(обмін["відповідь"]["body"])
            заміни.append({"файл": ім, "слот": запит["replacement"]["slot"],
                           "відхилено": запит["replacement"]["rejected"]["name"],
                           "статус": обмін["відповідь"]["status"],
                           "текст": відповідь["content"][0]["text"]})
    проксі = git("show", ЗАПИС + ":" + СЦЕНА + "проксі.txt").decode()
    лог = git("show", ЗАПИС + ":" + СЦЕНА + "лог.txt").decode().splitlines()
    результат = обєкт("результат.json")
    код_проксі = "аудит/ноутбук_стенд_2/проксі_почергове.js"
    sha_проксі = hashlib.sha256((КОРІНЬ / код_проксі).read_bytes()).hexdigest()
    джерела = ["джерела/показ/картки.js", "джерела/показ/міст.js", "джерела/заміна_речі.py",
               "джерела/міст_відповіді.py", "аудит/проби/рв6_стенд.js"]
    return {
        "запис_sha": ЗАПИС, "код_sha": КОД, "сцена": СЦЕНА, "файлів": len(файли),
        "обмінів": len(обміни),
        "статуси": {str(код): sum(о["відповідь"]["status"] == код for _, о in обміни)
                    for код in sorted({о["відповідь"]["status"] for _, о in обміни})},
        "текстових_відповідей": sum(ім.startswith("VIDPOVIDI/seed") for ім in імена),
        "модельних_викликів_у_підсумку": len(обєкт("знімки/модель_виклики.json")["виклики"]),
        "завершені_заміни_в_обмінах": заміни,
        "заміна_руки_1": обєкт("знімки/заміна_руки_1.json"),
        "артефакти_руки_2": [ім for ім in імена if "заміна_руки_2" in ім or "zamina_ruka2" in ім],
        "проксі": {"рядків": len(проксі.splitlines()), "перемикань": проксі.count("перемикання #"),
                    "sha256": sha_проксі, "збіг_із_запуском": sha_проксі == результат["проксі_sha256"]},
        "лог_заміни": [{"рядок": і+1, "текст": р} for і, р in enumerate(лог)
                        if "ЗАМІНА руки" in р or "стенд не піднявся:" in р],
        "повтор_змінні": обєкт("повтор.json")["змінні"],
        "доказ_обрив": обєкт("знімки/доказ.json")["обрив"],
        "незмінені_джерела_проти_живого": {
            ім: (КОРІНЬ / ім).read_bytes().replace(b"\r\n", b"\n") == git("show", КОД+":"+ім)
            for ім in джерела},
        "межа": "Обміни пишуться при відповіді; початок запиту і стан руки 2 при обриві не записані.",
    }


if __name__ == "__main__":
    print(json.dumps(вимір(), ensure_ascii=False, indent=2))
