/* Дим справжнього показу: обидві руки, відповідь/відмова/збій і незавершена модель.
   Запуск із кореня: NODE_PATH=<jsdom, fake-indexeddb> node <цей файл>.
   Міст і модель — заглушки; це не відтворення причини живого таймауту. */
const fs = require('fs'), path = require('path'), assert = require('assert/strict');
const {createRequire} = require('module');
const джерела = path.resolve(__dirname, '../../..', 'джерела');
const файл = path.join(джерела, 'тест_показу.js');
const код = fs.readFileSync(файл, 'utf8').split('\n(async () => {')[0];
assert(код.length < fs.statSync(файл).size, 'Не знайдено межі помічників батареї');
const {сторінка, чекатиСтарт} = new Function('require', '__dirname', 'process',
  код + '\nreturn {сторінка, чекатиСтарт};')(createRequire(файл), джерела, process);

async function перевірити(результат){
  const {дом, w, d, помилки} = сторінка({url: 'https://example.test/'});
  try {
    await чекатиСтарт(w);
    const стара = {id:'ж-1@example.test', назва:'Сукня', ціна:1000, слот:'сукня', фото:null};
    const нова = {...стара, id:'ж-2@example.test', назва:'Інша сукня'};
    const картки = ['3','4','1','2'].map(рука => ({рука, речі:[{...стара}],
      мітки:[], знахідки:[], питання:[], етапи:{}, свідомі:[]}));
    w.__пакет = {прогін:'дим', картки, знімок:{вхід:{}}};
    w.eval('П = window.__пакет; рендер(); режим("образи"); вхідМостаП = () => ({});'
      + 'мовоюКарткуП = async () => {}; window.зберегтиОбраз = async () => {};'
      + 'повідомленнямП = async () => ({тексти:{нема:"Заміни нема", відмова:"Збій"}});');
    await new Promise(так => setImmediate(так)); // Пейджер обробляє початкове додавання карток.
    // Як у записі: руки 1 і 2 на позиціях 2 і 3, заміни послідовні в одному прогоні.
    for (const рука of ['1','2']){
      const поз = картки.findIndex(к => к.рука === рука);
      w.eval(`показатиОбраз(${поз})`);
      const інші = JSON.stringify(картки.filter(к => к.рука !== рука));
      let завершитиМодель, відхилитиМодель, викликів = 0;
      const запити = [];
      w.__міст = async (ім, дані) => {
        if (ім === 'показ') return [нова];
        assert.equal(ім, 'від_моделі');
        запити.push(дані);
        return {заміна: дані.заміна.текст === undefined
          ? {готово:false, запити:[{ключ:'replace', чого:'replace_item', текст:'дим'}]}
          : результат === 'нема' ? {готово:true, чому:'replacement_model_found_none'}
          : {готово:true, річ:нова}};
      };
      w.__модель = () => { викликів++; return new Promise((так, ні) => {
        завершитиМодель = так; відхилитиМодель = ні;
      }); };
      w.eval('містП = (...а) => window.__міст(...а); модельП = (...а) => window.__модель(...а);');
      const кнопка = d.querySelector('#к-' + поз + ' button.замін');
      assert(кнопка, 'Нема кнопки заміни');
      w.__кнопка = кнопка;
      const дія = w.eval(`замінитиРічП(${поз}, "ж-1@example.test", window.__кнопка)`);
      await new Promise(так => setImmediate(так));
      // Незавершена відповідь лишає той самий стан очікування, що читає живий стенд.
      assert.equal(викликів, 1);
      assert(w.eval(`ЗАМІНИ_П.has(П.картки[${поз}])`));
      assert.equal(w.eval(`(П.картки[${поз}].етапи.заміни || []).length`), 0);
      assert(кнопка.disabled);
      assert.equal(запити[0].рука, рука);
      assert.equal(запити[0].донор, рука === '2');
      if (результат === 'збій') відхилитиМодель(new Error('дим: обрив відповіді'));
      else завершитиМодель('["#1·1"]');
      await дія;
      const етап = w.eval(`П.картки[${поз}].етапи.заміни.at(-1)`);
      assert(етап.закінчено);
      assert(!w.eval(`ЗАМІНИ_П.has(П.картки[${поз}])`));
      assert.equal(d.querySelectorAll('#к-' + поз + ' button.замін:disabled').length, 0);
      assert.equal(w.eval(`П.картки[${поз}].речі[0].id`), результат === 'успіх' ? нова.id : стара.id);
      assert.equal(JSON.stringify(картки.filter(к => к.рука !== рука)), інші);
      assert.equal(!!етап.помилка, результат === 'збій');
      assert.deepEqual(помилки, []);
      console.log(JSON.stringify({рука, результат, очікування_відтворено:true,
        закінчено:true, викликів_моделі:викликів, кнопки_живі:true, інші_картки_без_змін:true}));
    }
  } finally { дом.window.close(); }
}

(async () => {
  for (const результат of ['успіх', 'нема', 'збій']) await перевірити(результат);
  console.log('ДИМ: 6/6; жива причина не встановлена цим димом');
})().catch(помилка => { console.error(помилка); process.exitCode = 1; });
