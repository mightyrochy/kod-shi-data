/* Перший збалансований {…} у промпті: повтор формату дописує текст після JSON. */
function першийОбʼєкт(т) {
  const а = т.indexOf('{'); if (а < 0) return null;
  let глиб = 0, уРядку = false, екр = false;
  for (let і = а; і < т.length; і++) {
    const с = т[і];
    if (уРядку) { if (екр) екр = false; else if (с === '\\') екр = true; else if (с === '"') уРядку = false; continue; }
    if (с === '"') уРядку = true;
    else if (с === '{') глиб++;
    else if (с === '}' && --глиб === 0) { try { return JSON.parse(т.slice(а, і + 1)); } catch (_) { return null; } }
  }
  return null;
}
