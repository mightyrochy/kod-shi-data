"""Зводить завершені виміри й окремо називає зупинений надлишковий запуск."""
from datetime import datetime, timezone
import json
from pathlib import Path
import re
import subprocess
import sys

Д = Path(__file__).resolve().parent
К = Д.parents[2]
def читати(назва):
    """Читає завершений JSON-вимір."""
    return json.loads((Д / назва).read_text("utf8"))

до, після = читати("до.json"), читати("після.json")
assert до["порушень"] == 74 and після["порушень"] == 0
батарея = читати("батарея.json")
провали = [р for р in батарея if р["код"]]
assert len(батарея) == 14 and len(провали) == 1 and "підтон_v03_009" in провали[0]["команда"][0]
assert читати("підтон-повтор.json")["код"] == 0
assert читати("повтор-pal_K-PAL-02.json")["код"] == 0
assert all(р["пройдено"] for р in читати("розділ-повтор.json"))
assert all(р["код"] == 0 for р in читати("повтор-ворота.json"))
лічба = lambda назва: int(re.search(r"місць: (\d+)\s*$", (Д / назва).read_text("utf8"))[1])
assert лічба("прилад-до.txt") == 166 and лічба("прилад-остаточний.txt") == 158
assert читати("прилад-остаточний-час.json")["код"] == 0
джерела = {}
for дж in ("model_hex", "spectro"):
    пари = [(а, б) for а, б in zip(до["записи"], після["записи"]) if а["джерело"] == дж]
    assert len(пари) == 9 and all(а["профіль"] == б["профіль"] for а, б in пари)
    джерела[дж] = {к: sum(а[к] != б[к] for а, б in пари) for к in ("основи", "схеми")}
знімок = читати("знімок.json")
assert not знімок["помилки"] and not знімок["контраст"]["доступно"]
assert знімок["осі"] == dict(value="withheld", chroma="withheld", hue="withheld")
записи = читати("сцени-порівняння.json")
assert len(записи) == 2 and all(not р["нових"] and len(р["відхилено_після"]) == 13 for р in записи)
результат = dict(
    час_UTC=datetime.now(timezone.utc).isoformat(),
    база="6be1a61aef08e31f396ca84d5ce4747ca5218e22",
    код_продукту="935619afdfb3e31eb1ae1e8e9c413ff588b54e37",
    середовище=dict(python=sys.version, node=subprocess.check_output(["node", "--version"], text=True).strip(),
                    компілятор_показу="CPython 3.12.1", платформа=sys.platform),
    ризик="Р3", прилад=dict(до=166, після=158, змінено=False, секунд_після=читати("прилад-остаточний-час.json")["секунд"],
                          команда="python -W ignore джерела/прилади/корінь_річ_ознаки_обличчя.py"),
    точковий=dict(профілів=18, порушень_до=74, порушень_після=0, зміни_порад=джерела),
    спільна_батарея=dict(виконано=6, первинний_прогін_розділів="574/575", повтор_розділу="7/7",
                        показ="927 звірок у 74 розділах", контракт="код 0", протокол="код 0", дим="код 0"),
    своя_сімя=dict(перевірок=14, первинно_код_0=13, оновлено_очікування_воріт="підтон_v03_009", повтор="код 0"),
    повтор_після_воріт=читати("повтор-ворота.json"),
    записані_обміни=dict(викликів=171, винятків=0, відхилення=записи),
    додаткові_проби=dict(pal_K_PAL_01="код 0", pal_K_PAL_02="повтор код 0", pal_K_PAL_03="код 0",
                        надлишкова_пачка="зупинена на pal_K-PAL-04; не зарахована як повністю виконана; батарея-надлишкова.json"),
    збірка=dict(режим="показ-повний", відбиток_коду="3d04a44e80a5", звірка_вантажу="код 0", знімок=знімок,
                фото=читати("фото-джерела.json")),
    корінь="ЧАСТКОВО; наряд і рядки 10704/12010 залишаються; решта читачів за переліком приладу",
    живе_приймання=["ж4_робота — палітра", "ж1_свято_тріада — палітра", "ж2_побачення_вечір — повне"],
    нових_вад_поза_мірилом=0,
)
(Д / "вимір.json").write_text(json.dumps(результат, ensure_ascii=False, indent=2), "utf8")
print("остаточний вимір: 166 → 158; порушень 74 → 0; усі потрібні перевірки завершені")
