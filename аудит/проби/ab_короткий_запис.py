ЗОВНІШНІ_ВХОДИ = {
    "MODEL_URL": "адреса LM Studio ноутбука для `--модель` (типово http://127.0.0.1:1234/v1); "
                 "маршрут `claude-…` іде тим самим ендпойнтом мосту, що й у продукті",
}
АДРЕСА = (os.environ.get("MODEL_URL") or "http://127.0.0.1:1234/v1").rstrip("/")
СИМВ = dict(ensure_ascii=False, separators=(",", ":"))


def _модель(промпт, ід):
    """(текст відповіді, впало) від моделі форми OpenAI; без `--модель` — заглушка (None, None)."""
    if not ід:
        return None, None
    тіло = dict(model=ід, messages=[dict(role="user", content=промпт)], stream=False,
                max_tokens=int(os.environ.get("MODEL_MAX_TOKENS") or 4000))
    запит = urllib.request.Request(АДРЕСА + "/chat/completions",
                                   data=json.dumps(тіло, ensure_ascii=False).encode("utf-8"),
                                   headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(запит, timeout=3600) as в:
            дані = json.loads(в.read().decode("utf-8"))
        return ((дані.get("choices") or [{}])[0].get("message") or {}).get("content") or "", None
    except Exception as е:                            # noqa: BLE001 — впалий виклик названий, не ковтнутий
        return None, "%s: %s" % (type(е).__name__, е)


def плече(вх, короткий, ід_моделі):
    """Одне плече A/B: пул, пакет, відповідь моделі й вердикт коду над її образами."""
    КК.оголосити(короткий)
    МП._КЕШ_ПАКЕТА.clear()
    зп = json.loads(B.виклик("запити", json.dumps(dict(вх, короткий_запис=(1 if короткий else 0)),
                                                  ensure_ascii=False)))
    пакети = [p for p in МП._КЕШ_ПАКЕТА.values() if p.get("пакет")]
    пак = пакети[0]
    речі = [r for рч in пак["пакет"]["пул"].values() for r in рч]
    з_розбором, усього = КК.частка_з_розбором(речі)
    симв = [len(json.dumps(Д.річ(r, короткий=короткий), **СИМВ)) for r in речі]
    текст, впало = _модель(пак["текст"], ід_моделі)
    вих = dict(короткий=короткий, речей=усього, з_розбором=з_розбором,
               символів_пакета=len(пак["текст"]), симв_на_річ=st.median(симв) if симв else 0,
               особливостей=st.median([len(r.get("features") or "") for r in речі]) if речі else 0,
               впало=впало, образи=[], знахідки=[], запит=пак["текст"])
    if not текст:
        return вих
    # ВЕРДИКТ КОДУ — ТИМ САМИМ ШЛЯХОМ, ЩО В ПРОДУКТІ (`bridge.виклик("від_моделі")`): інакше
    # «суд» цього A/B був би другим судом, і його знахідки не можна було б порівняти з живими.
    вд = json.loads(B.виклик("від_моделі", json.dumps(dict(вх, текст_моделі=текст,
                                                           короткий_запис=(1 if короткий else 0)),
                                                      ensure_ascii=False)))
    for о in ((вд.get("вердикт") or {}).get("образи") or []):
        вих["образи"].append(dict(ід=о.get("ід"), підпис=о.get("підпис"),
                                  речі=list(о.get("речі") or []), опис=о.get("опис") or о.get("текст")))
        for з in (о.get("знахідки") or []):
            вих["знахідки"].append(dict(образ=о.get("ід"), регістр=з.get("регістр"),
                                        код=з.get("код"), суть=з.get("суть")))
    вих["зібрано"] = bool(зп)
    return вих


def жаккар(a, b):
    """Jaccard між наборами речей двох плечей — той самий вимір стабільності, що в В-1.
    None, коли жодне плече образів не дало: без моделі «0.00» читалось би як «вибір розійшовся
    повністю», хоч вибору не було зовсім (у хмарі міряється форма й лічба, не вибір)."""
    A = {і for о in a for і in о["речі"]}
    Б = {і for о in b for і in о["речі"]}
    if not (A or Б):
        return None
    return len(A & Б) / len(A | Б)


def _жк(ж):
    """Jaccard для аркуша: число або «—» (образів нема — порівнювати нічого)."""
    return "—" if ж is None else "%.2f" % ж


def звіт(a, b, куди):
    """Аркуш для ОЧЕЙ: числа обох плечей, вибір, суд і картки поруч. Повертає шлях."""
    os.makedirs(куди, exist_ok=True)
    шлях = os.path.join(куди, "ab_запис.txt")
    with io.open(шлях, "w", encoding="utf-8") as ф:
        ф.write("A/B ЗАПИСУ РЕЧІ В ПУЛІ (наряд К-3). A — запис як сьогодні, B — короткий запис.\n")
        ф.write("Бюджет символів той самий; міняється лише скільки речей у нього влазить.\n\n")
        for ім, п in (("A повний", a), ("B короткий", b)):
            ф.write("%-12s речей %4d (з розбором %4d) · пакет %6d симв. · %5.0f симв./річ · "
                    "особливості %3.0f симв.%s\n"
                    % (ім, п["речей"], п["з_розбором"], п["символів_пакета"], п["симв_на_річ"],
                       п["особливостей"], (" · ВИКЛИК ВПАВ: %s" % п["впало"]) if п["впало"] else ""))
        ф.write("\nречей у бюджеті: %d → %d (%+.0f %%)\n"
                % (a["речей"], b["речей"], 100.0 * b["речей"] / max(a["речей"], 1) - 100))
        ф.write("Jaccard вибору A/B: %s%s\n"
                % (_жк(жаккар(a["образи"], b["образи"])),
                   "  (образів нема: плечі прогнано без моделі)" if not (a["образи"] or b["образи"]) else ""))
        for ім, п in (("A повний", a), ("B короткий", b)):
            ф.write("\n── ВИБІР %s ────────────────────────────────────────────────\n" % ім)
            for о in п["образи"]:
                ф.write("  %-6s %s\n" % (о["ід"], ", ".join(о["речі"])))
            ф.write("── СУД %s (знахідки коду) ─────────────────────────────────\n" % ім)
            for з in п["знахідки"]:
                ф.write("  %-6s %-9s %-14s %s\n" % (з["образ"], з["регістр"] or "", з["код"] or "",
                                                    (з["суть"] or "")[:140]))
            ф.write("── КАРТКИ %s (підпис, опис, склад) ───────────────────────\n" % ім)
            for о in п["образи"]:
                ф.write("  %s · %s\n     %s\n     %s\n" % (о["ід"], о["підпис"] or "(без підпису)",
                                                           (о["опис"] or "(опису нема)")[:600],
                                                           ", ".join(о["речі"])))
        for ім, п in (("A", a), ("B", b)):
            with io.open(os.path.join(куди, "запит_%s.json" % ім), "w", encoding="utf-8") as зф:
                зф.write(п["запит"])
    return шлях


def головна(арг=None):
    п = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    п.add_argument("--модель", default=None, help="ід моделі LM Studio або claude-…; без неї заглушка")
    # ТИПОВО — ТИМЧАСОВА ТЕКА, А НЕ РЕПОЗИТОРІЙ (28.09.2026, знахідка перевірки #425).
    # Доти типовим `--куди` було `аудит/тести/ab_запис`, і проба, запущена БЕЗ аргументів,
    # писала туди три файли (`ab_запис.txt`, `запит_A.json`, `запит_B.json`, ~270 КБ). Поки
    # її ганяли руками з явним `--куди`, це було непомітно; щойно `прилади/лічба_проб.py`
    # погнав усі проби поспіль, вони поїхали в коміт як «випадкові файли». Прогін проби не
    # має бруднити дерево: хто хоче лишити аркуші собі, каже `--куди` сам (рядки прикладів
    # нагорі саме такі й лишились).
    п.add_argument("--куди", default=os.path.join(tempfile.gettempdir(), "ab_запис"))
    п.add_argument("--сід", type=int, default=None, help="сід прогону; типово — сід стенда")
    п.add_argument("--розбір", default=None, help="файл розбору; без нього — заглушка Н-1")
    к = п.parse_args(арг)
    os.chdir(ДЖЕРЕЛА)
    os.environ["ROZBIR_KODY"] = (к.розбір or os.environ.get("ROZBIR_KODY")
                                 or ЗР.зібрати(os.path.join(tempfile.gettempdir(),
                                                            КК.РОЗБІР_ІМ + ".gz"))[0])
    вх = dict(json.load(io.open("стенд_вх.json", encoding="utf-8")), каталог=Ф.каталог_на_диску())
    if к.сід:
        вх["сід"] = к.сід
    print("A/B запису речі · сід %s · модель %s · розбір %s"
          % (вх.get("сід"), к.модель or "(заглушка: лише форма й лічба)", os.environ["ROZBIR_KODY"]))
    a = плече(вх, False, к.модель)
    b = плече(вх, True, к.модель)
    шлях = звіт(a, b, к.куди)
    print("A повний   : речей %4d, %6d симв. пакета, %4.0f симв./річ"
          % (a["речей"], a["символів_пакета"], a["симв_на_річ"]))
    print("B короткий : речей %4d, %6d симв. пакета, %4.0f симв./річ, особливості %.0f симв."
          % (b["речей"], b["символів_пакета"], b["симв_на_річ"], b["особливостей"]))
    print("РЕЧЕЙ У БЮДЖЕТІ: %d → %d (%+.0f %%) · Jaccard вибору %s · очима: %s"
          % (a["речей"], b["речей"], 100.0 * b["речей"] / max(a["речей"], 1) - 100,
             _жк(жаккар(a["образи"], b["образи"])), шлях))
    return 0


if __name__ == "__main__":
    sys.exit(головна())
