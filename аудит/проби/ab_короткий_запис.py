"""ab_короткий_запис.py — A/B: ТОЙ САМИЙ СЦЕНАРІЙ І СІД ДВОМА ЗАПИСАМИ РЕЧІ (наряд К-3).

ЧОМУ ЦЕ Є (рішення власника 27.09.2026, `аудит/ПЕРЕДАЧА.md` §0 п. 4, дослівно): «ПЕРЕД
переключенням — A/B: той самий пул і сценарій словами крамниці vs кодами+рядком, на моделі
ноутбука й на Claude; порівняти вибір, суд, картки очима; перемикати лише якщо не гірше і
описи образів не стали загальнішими». Отже цей скрипт НЕ вирішує — він кладе поруч два плеча
так, щоб власник і менеджер могли подивитись очима, і рахує те, що можна порахувати.

ДВА ПЛЕЧА, І ТРЕТЄ ЧИСЛО. Плече A — запис як сьогодні (`короткий_запис` вимкнено), плече B —
короткий запис при ТОМУ САМОМУ бюджеті символів, тож у плечі B в пул влазить інша кількість
речей: саме це й міряється («більше речей за той самий обсяг» — гіпотеза власника, і скрипт
має право її не підтвердити). Сід, сценарій, профіль і каталог — ті самі в обох плечах.

ЩО ДРУКУЄТЬСЯ І ЩО ЛЯГАЄ У ФАЙЛ ДЛЯ ОЧЕЙ:
  · на кожне плече — частка речей пулу з розбором, символів на річ (медіана) і речей у бюджеті;
  · вибір: номери речей кожного образу і Jaccard між плечима (той самий вимір, що в В-1);
  · суд: знахідки коду на образах кожного плеча (регістр і код правила);
  · картки: підпис, опис і склад кожного образу — поруч, плече A ліворуч, плече B праворуч.
МОДЕЛЬ — ПАРАМЕТРОМ: `--модель` (LM Studio ноутбука, `MODEL_URL`) або `--модель claude-…`
(тим самим шляхом, яким її кличе продукт через міст). Без `--модель` — ЗАГЛУШКА: у хмарі
міряється форма й лічба, живий A/B робить ноутбук після розбору пулу.

ПРОГІН (хмара, форма й лічба):
  python3 аудит/проби/ab_короткий_запис.py --куди аудит/тести/ab_запис
ПРОГІН (ноутбук, наживо; LM Studio слухає 127.0.0.1:1234):
  python3 аудит/проби/заглушка_розбору.py --куди джерела/каталог_розбір_коди.json.gz   # або справжній розбір
  python3 аудит/проби/ab_короткий_запис.py --модель mamaylm-gemma-3-12b-it-v2.0 --куди аудит/тести/ab_запис
  python3 аудит/проби/ab_короткий_запис.py --модель claude-opus-5 --куди аудит/тести/ab_запис_claude
"""
