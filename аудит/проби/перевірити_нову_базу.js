/* Проба `нова_база.js` на справжньому записі концерту 28.10 у тимчасовому git-дереві: завершений автоживий на
   голові main стає датованою базою з номерами відомих червоних, а застарілий, незавершений чи з новою червоною — ні. */
const assert = require('node:assert/strict');
const fs = require('fs'), path = require('path'), os = require('os');
const {spawnSync} = require('child_process');
const {виконати, живийШлях} = require('./нова_база.js');
const {свіжіЗаписи, результатСтенда, вікДіб} = require('./приймання_записів.js');
const {звіритиБазу, порівняти} = require('./храповик_записів.js');

const запис = path.join(__dirname, 'нічні/20261028/б1_концерт_стримано');
const корінь = fs.mkdtempSync(path.join(os.tmpdir(), 'нова-база-'));
const git = (...а) => {
  const р = spawnSync('git', а, {cwd: корінь, encoding: 'utf8'});
  assert.equal(р.status, 0, р.stderr);
  return р.stdout.trim();
};
const писати = (файл, текст) => {
  fs.mkdirSync(path.dirname(path.join(корінь, файл)), {recursive: true});
  fs.writeFileSync(path.join(корінь, файл), текст);
};
const комітувати = повідомлення => { git('add', '-A', '--', '.', ':(exclude)аудит/проби/автоживий-проба'); git('commit', '-qm', повідомлення); return git('rev-parse', 'HEAD'); };
const тихо = функція => { const log = console.log; console.log = () => {}; try { return функція(); } finally { console.log = log; } };

try {
  git('init', '-q', '-b', 'main');
  git('config', 'user.email', 'проба@local'); git('config', 'user.name', 'проба');
  писати('джерела/код.py', 'А = 1\n');
  писати('аудит/проби/рв6_стенд.js', "require('./записаний_обмін.js');\nrequire(path.join(__dirname, 'записи_шару.js'));\n" +
    "const п = path.join(__dirname, 'рв6_правило_руки2.py');\n");
  писати('аудит/проби/записаний_обмін.js', '// обмін\n');
  писати('аудит/проби/записи_шару.js', "require('./часи_збору.js');\n");
  писати('аудит/проби/часи_збору.js', '// час\n');
  писати('README.md', 'проба\n');
  писати('джерела/аудит/ДОСЯЖНІСТЬ.md', 'звіт збірки 1\n');
  писати('аудит/проби/рв6_правило_руки2.py', '# правило\n');
  писати('аудит/проби/жінки/ж8.json', '{}\n');
  // Попередня база — та сама сцена 27.10 з відомою червоною 10274.
  const стара = path.join(корінь, 'аудит/проби/нічні/20261027/б1_концерт_стримано');
  fs.cpSync(запис, стара, {recursive: true});
  fs.rmSync(path.join(стара, 'походження.json'));
  const а = комітувати('база 27.10');
  assert.deepEqual(живийШлях(корінь), ['джерела', 'аудит/проби/жінки', 'аудит/проби/записаний_обмін.js',
    'аудит/проби/записи_шару.js', 'аудит/проби/рв6_правило_руки2.py', 'аудит/проби/рв6_стенд.js', 'аудит/проби/часи_збору.js',
    ':(exclude)джерела/аудит/ДОСЯЖНІСТЬ.md'], 'місцеві залежності й файли стенда — транзитивно');
  // Форма справжньої збірки: штамп build.txt — коміт джерел, коміт «збірка:» CI після нього міняє index.html,
  // build.txt і звіт `джерела/аудит/ДОСЯЖНІСТЬ.md` (11220, 11221).
  писати('index.html', 'const ЗБІРКА_ПОКАЗУ = "' + а + '"\n'); писати('build.txt', а + '\n');
  писати('джерела/аудит/ДОСЯЖНІСТЬ.md', 'звіт збірки 2\n');
  комітувати('збірка: ' + а);

  // Запис автоживого так, як його пише `записати_сцену.py`: без бази й походження.
  const наряд = path.join(корінь, 'аудит/проби/автоживий-проба');
  const записати = (sha, початок, зміна = null) => {
    const тека = path.join(наряд, 'б1_концерт_стримано');
    fs.rmSync(наряд, {recursive: true, force: true});
    fs.cpSync(запис, тека, {recursive: true});
    for (const ф of ['база.json', 'походження.json']) fs.rmSync(path.join(тека, ф));
    const р = JSON.parse(fs.readFileSync(path.join(тека, 'результат.json'), 'utf8'));
    fs.writeFileSync(path.join(тека, 'результат.json'), JSON.stringify({...р, sha, початок, rc: 1}, null, 1));
    if (зміна) зміна(тека);
    return тека;
  };
  const підсумок = () => fs.readFileSync(path.join(наряд, 'НОВА_БАЗА.md'), 'utf8');

  // 1. Голова main: запис стає базою 30.10, червона отримує номер попередньої бази — з дерева main, навіть коли
  // копія наряду не виклала велику теку старої бази (sparse-checkout обгортки).
  let тека = записати(а, '2026-10-30T01:00:00+00:00');
  fs.rmSync(стара, {recursive: true});
  // Збій переносу (EPERM на Windows) нічого не лишає: ні бази в записі, ні теки дати; повтор проходить (11222).
  const перейменувати = fs.renameSync;
  fs.renameSync = () => { throw Object.assign(new Error('зайнято'), {code: 'EPERM'}); };
  try { assert.equal(тихо(() => виконати([наряд, '--main', 'main'], корінь)), 3); }
  finally { fs.renameSync = перейменувати; }
  assert.match(підсумок(), /не база — перенос не вдався \(EPERM\)/);
  assert.ok(fs.existsSync(тека) && !fs.existsSync(path.join(тека, 'база.json')));
  assert.ok(!fs.existsSync(path.join(корінь, 'аудит/проби/нічні/20261030')));
  assert.equal(тихо(() => виконати([наряд, '--main', 'main'], корінь)), 0);
  git('checkout', '--', 'аудит/проби/нічні/20261027');
  const нова = path.join(корінь, 'аудит/проби/нічні/20261030/б1_концерт_стримано');
  assert.ok(!fs.existsSync(тека), 'запис перенесено, не скопійовано');
  const база = JSON.parse(fs.readFileSync(path.join(нова, 'база.json'), 'utf8'));
  звіритиБазу(база);
  assert.equal(база.sha, а);
  assert.deepEqual(база.звірки.filter(з => !з.зелена).map(з => з.вада), [10274]);
  const походження = JSON.parse(fs.readFileSync(path.join(нова, 'походження.json'), 'utf8'));
  assert.equal(походження.замінює, 'аудит/проби/нічні/20261027/б1_концерт_стримано');
  assert.equal(походження.вік_заміненої_діб, 3);
  assert.match(підсумок(), /^НОВА БАЗА: аудит\/проби\/нічні\/20261030\/б1_концерт_стримано замінює аудит\/проби\/нічні\/20261027\/б1_концерт_стримано \(вік заміненої 3 діб\)/m);
  // Приймання бере новий запис і звіряє його повністю: той самий живий вимір — без регресу й без застарілого виклику.
  const свіжа = свіжіЗаписи(path.join(корінь, 'аудит/проби/нічні'));
  assert.deepEqual(свіжа.map(з => path.relative(корінь, з.тека)), ['аудит/проби/нічні/20261030/б1_концерт_стримано']);
  const повтор = результатСтенда(нова, 1);
  assert.equal(повтор.звірки.length, 77);
  assert.deepEqual(порівняти(база, повтор), {стан: 'без регресу', регресії: [], покращення: []});
  assert.equal(вікДіб(нова, Date.UTC(2026, 9, 31, 12)), 1);
  git('add', '-A', '--', '.', ':(exclude)аудит/проби/автоживий-проба'); git('commit', '-qm', 'нова база');

  // 2. Документи після SHA запису живого шляху не змінюють; друга база того самого дня — окрема тека з часом.
  писати('README.md', 'документ\n');
  const б = комітувати('документ');
  записати(а, '2026-10-30T05:07:00+00:00');
  assert.equal(тихо(() => виконати([наряд, '--main', б], корінь)), 0);
  assert.ok(fs.existsSync(path.join(корінь, 'аудит/проби/нічні/20261030T0507/б1_концерт_стримано/база.json')));
  assert.match(підсумок(), /замінює аудит\/проби\/нічні\/20261030\/б1_концерт_стримано \(вік заміненої 0 діб\)/);
  git('add', '-A', '--', '.', ':(exclude)аудит/проби/автоживий-проба'); git('commit', '-qm', 'друга база дня');

  // 3. Не база: змінено продукт чи місцеву залежність стенда після SHA, rc 2, чужий SHA, старіший запис.
  const відмова = (sha, main, шаблон, початок = '2026-10-31T01:00:00+00:00', зміна = null) => {
    тека = записати(sha, початок, зміна);
    assert.equal(тихо(() => виконати([наряд, '--main', main], корінь)), 3, String(шаблон));
    assert.match(підсумок(), шаблон);
    assert.ok(fs.existsSync(тека) && !fs.existsSync(path.join(тека, 'база.json')), 'запис лишається без бази');
  };
  писати('джерела/код.py', 'А = 2\n');
  const в = комітувати('продукт');
  відмова(б, в, /не база — живий шлях змінено після [0-9a-f]{40}: джерела\/код\.py/);
  писати('аудит/проби/часи_збору.js', '// інший час\n');
  const г = комітувати('стенд');
  відмова(в, г, /живий шлях змінено .*аудит\/проби\/часи_збору\.js/);
  відмова(г, г, /стенд не завершився \(rc=2\)/, undefined, т => {
    const р = JSON.parse(fs.readFileSync(path.join(т, 'результат.json'), 'utf8'));
    fs.writeFileSync(path.join(т, 'результат.json'), JSON.stringify({...р, rc: 2}));
  });
  git('checkout', '-qb', 'бічна', а); писати('бічне.txt', '1\n');
  const бічний = комітувати('бічний'); git('checkout', '-q', 'main');
  відмова(бічний, г, /не предок/);
  відмова(г, г, /новіша база вже є: аудит\/проби\/нічні\/20261030T0507/, '2026-10-29T01:00:00+00:00');

  // 4. Нова червона без номера — знахідка: бази нема, запис лишається доказом.
  тека = записати(г, '2026-10-31T01:00:00+00:00', т => {
    const лог = fs.readFileSync(path.join(т, 'лог.txt'), 'utf8').replace(/^ВПАЛО 1 ·/m, 'ВПАЛО 2 ·');
    fs.writeFileSync(path.join(т, 'лог.txt'), лог + '\n  ✗ нова червона  →  не відсічено\n');
  });
  assert.equal(тихо(() => виконати([наряд, '--main', г], корінь)), 4);
  assert.match(підсумок(), /^ЗНАХІДКА: б1_концерт_стримано — червона звірка без номера в попередній базі аудит\/проби\/нічні\/20261030T0507\/б1_концерт_стримано/m);
  assert.ok(fs.existsSync(тека) && !fs.existsSync(path.join(тека, 'база.json')));
  assert.ok(!fs.existsSync(path.join(корінь, 'аудит/проби/нічні/20261031')));

  // 5. Порожня тека наряду — бази нема, підсумок про це каже.
  fs.rmSync(наряд, {recursive: true}); fs.mkdirSync(наряд);
  assert.equal(тихо(() => виконати([наряд, '--main', г], корінь)), 3);
  assert.match(підсумок(), /бази нема/);
  console.log('нова база: 5 груп перевірок зелені');
} finally {
  fs.rmSync(корінь, {recursive: true, force: true});
}
