"""РВ-3 · Р-3 (Т-08 крок 5): відповіді про драпіровку з чату живуть один хід.
Показ шле в `паспорт` лише `драп_сирий` із КАРТОК (усі null, доки жінка їх не торкалась)
і «паспорт досі», а `драп_сирий` у СХЕМА_ПАСПОРТА не оголошений — з «паспорта досі»
він випадає. Запуск із теки `джерела`: python3 ../аудит/проби/рв3_драп_у_чаті.py"""
import json
import bridge as B, pipeline as PL

PL.Р3 = PL.Р3_ЗАВЖДИ            # обидва варіанти рішення ставлять питання; міряємо, що буде після відповіді
сц = dict(нагода="побачення", місце="ресторан_районний", година=19, темп_c=12)
картки = dict(білий=None, метал=None, нейтралі=None, барви=None)   # рівно те, що шле вхідМостаП: п.драп
історія = [dict(хто="людина", текст="побачення в ресторані"),
           dict(хто="ші", текст="Золото чи срібло? Оптичний чи вершковий білий? Теплі чи холодні нейтралі?"),
           dict(хто="людина", текст="золото; білий — не бачу різниці")]
# хід 1: модель відповіла на питання драпіровки
п1 = PL.паспорт_з_json(json.dumps(dict(подія="побачення в ресторані", нагода="побачення",
                                      драп_сирий=dict(метал="золото", білий="не бачу різниці")), ensure_ascii=False), сц, "")
print("хід 1 · паспорт.драп_сирий =", п1.get("драп_сирий"))
# хід 2: жінка додає ще одне слово; показ шле паспорт досі + драп із карток
пр = json.loads(B.виклик("паспорт", json.dumps(dict(сценарій=сц, вимоги="", паспорт=п1, драп_сирий=картки,
     історія=історія + [dict(хто="людина", текст="і без підборів")]), ensure_ascii=False)))["промпт"]
досі = [р for р in пр.split("\n") if р.startswith("Паспорт досі")][0]
print("хід 2 · «Паспорт досі» несе драп_сирий:", "драп_сирий" in досі)
print("хід 2 · питання драпіровки ставляться знову:", "Драпіровки (що їй до лиця) ще нема" in пр)
# хід 2 · модель відповідей ходу 1 не бачить і в JSON їх не повторює; розбір іде тим самим
# шляхом, що й у показі (`паспортПоРозмовіП`: та сама база — і в промпт, і в розбір)
п2 = json.loads(B.виклик("паспорт", json.dumps(dict(сценарій=сц, вимоги="", паспорт=п1, драп_сирий=картки,
     json_моделі=json.dumps(dict(подія="побачення в ресторані", нагода="побачення",
                                 вето=dict(типи=["підбори"])), ensure_ascii=False)), ensure_ascii=False)))["паспорт"]
вх = B._застосувати_паспорт(dict(сценарій=сц, паспорт=п2, драп_сирий=картки))
print("хід 2 · паспорт.драп_сирий =", п2.get("драп_сирий"), "· у вхід моста їде драп_сирий =", вх.get("драп_сирий"))
print("→ відповіді ходу 1 %s" % ("збережено" if (вх.get("драп_сирий") or {}).get("метал") else "ВТРАЧЕНО: у палітру самозвіт не дійде, а чат спитає втретє"))
