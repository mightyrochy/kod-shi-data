"""Повторює текстові поля 144 сторінок і зберігає їхнє покриття без мережі.

Запуск із кореня: python -X utf8 аудит/проби/річ_запис_межі.py --вихід файл.json.gz
Джерело знаменників — непорожні поля PR #2514 після виключень очі_п3.json.
Нові поля не збільшують знаменника.
Це перевірка наявності й походження, а не незалежне оцінювання правильності тексту.
"""
import argparse
from collections import Counter
import gzip
import hashlib
import json
from pathlib import Path
import sys

КОРІНЬ = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРІНЬ / 'zhnyvarka'))
import жниварка
import виконавець


def виміряти(вихід):
    """Звіряє обидва збирачі на всій вибірці та рахує наявні текстові поля."""
    тека = КОРІНЬ / 'аудит/проби/річ_запис_каталог_2026_10_30'
    вибірка = json.loads((тека / 'вибірка_п3.json').read_text(encoding='utf8'))
    виключення = {(р['id'], р['поле']) for р in json.loads((тека / 'очі_п3.json').read_text(encoding='utf8'))
                  if р['вердикт'] == 'виключено'}
    лічба, сторінки = Counter(), []
    for рядок in вибірка:
        дані = (тека / рядок['файл']).read_bytes()
        тіло = gzip.decompress(дані).decode('utf8')
        рецепт = жниварка.рецепт_селекторів(рядок['крамниця'])
        факти = жниварка.факти_з_картки(тіло, рядок['url'], рецепт)
        картка = виконавець.картка_з_dom(рядок['url'], тіло, {}, факти)
        for поле in ('назва', 'опис'):
            if (картка.get(поле) or '') != (факти.get(поле) or '')[:200 if поле == 'назва' else 4000]:
                raise AssertionError(f'{рядок["url"]}: збирачі розійшлись у полі {поле}')
            було = bool((рядок.get(поле) or '').strip()) and (рядок['id'], поле) not in виключення
            є = bool((факти.get(поле) or '').strip())
            лічба[f'{поле}_вибірки'] += було
            лічба[f'{поле}_покрито'] += було and є
            лічба[f'{поле}_усіх'] += є
        лічба['блоків'] += факти.get('межа_блоку') in ('рецепт', 'itemtype')
        лічба['товарів'] += bool(факти.get('є_товар'))
        сторінки.append(dict(url=рядок['url'], крамниця=рядок['крамниця'], файл=рядок['файл'],
                            sha256=hashlib.sha256(дані).hexdigest(), рецепт=рецепт,
                            межа=факти.get('межа_блоку'), назва=факти.get('назва'),
                            назва_джерело=факти.get('назва_джерело'), опис=факти.get('опис'),
                            опис_джерело=факти.get('опис_джерело'),
                            назва_вибірки=рядок['назва'], опис_вибірки=рядок['опис']))
    джерела = {шлях: hashlib.sha256((КОРІНЬ / шлях).read_bytes()).hexdigest()
               for шлях in ('zhnyvarka/жниварка.py', 'zhnyvarka/виконавець.py', 'zhnyvarka/рецепти.tsv')}
    результат = dict(лічба=dict(лічба), джерела_sha256=джерела, сторінки=сторінки)
    вихід.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(вихід, 'wt', encoding='utf8') as файл:
        json.dump(результат, файл, ensure_ascii=False, indent=2)
    print(json.dumps(dict(лічба), ensure_ascii=False))
    return 0 if лічба['назва_покрито'] >= 133 and лічба['опис_покрито'] >= 100 else 1


def main():
    """Приймає шлях доказів і повертає результат порогів наряду."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('--вихід', type=Path, required=True)
    арг = парсер.parse_args()
    return виміряти(арг.вихід)


if __name__ == '__main__':
    raise SystemExit(main())
