# -*- coding: utf-8 -*-
"""Міряє K-JEW-01 на всіх парах каталогу й чотирьох тілах без викликів моделі.

З кореня: python аудит/проби/Е3_ч38_кольє_каталог.py --вихід <до.json.gz>
Той самий запуск після правки; --звірити <до.json.gz> <після.json.gz> друкує переходи.
"""
import argparse
import collections
import contextlib
import gzip
import io
import json
import os
from pathlib import Path
import sys


def читати(шлях):
    """Читає стислий запис виміру."""
    with gzip.open(шлях, "rt", encoding="utf-8") as ф:
        return json.load(ф)


def звірити(до, після):
    """Порівнює кожну пару за тілом, правилом, силою й вагою, друкує приклади."""
    д, п = читати(до), читати(після)
    assert д["каталог"] == п["каталог"], "різні каталоги"
    for назва, старе in д["тіла"].items():
        нове = п["тіла"][назва]
        assert старе["пари"].keys() == нове["пари"].keys(), "змінився обсяг пар"
        переходи, приклади = collections.Counter(), {}
        for пара, вердикт in старе["пари"].items():
            наступний = нове["пари"][пара]
            if вердикт != наступний:
                к = json.dumps([вердикт, наступний], ensure_ascii=False)
                переходи[к] += 1
                приклади.setdefault(к, пара)
        print(назва, "пар", len(старе["пари"]), "змінено", sum(переходи.values()),
              "переходи", dict(переходи), "приклади", приклади)
        for мітка, запис in (("ДО", старе), ("ПІСЛЯ", нове)):
            приклад = запис["приклад"]
            if приклад:
                print("  приклад", мітка, приклад["кольє"], "×", приклад["верх"], приклад["пояснення"])


def вимір(вихід):
    """Виконує живий шлях завантаження каталогу та судить кожну придатну пару."""
    корінь = Path(__file__).resolve().parents[2]
    код = корінь / "джерела"
    os.chdir(код)
    sys.path.insert(0, str(код))
    import accessory as АК
    import bridge as М
    import feed as Ф
    import fit as ПС

    вхід = json.loads((код / "стенд_вх.json").read_text(encoding="utf-8"))
    вхід.update(каталог=Ф.каталог_на_диску(str(код / "каталог_повний.xml")), гілка=0)
    with contextlib.redirect_stdout(io.StringIO()):
        json.loads(М.виклик("запити", json.dumps(вхід, ensure_ascii=False)))
    каталог = М.каталог_останнього_пакета()
    _, стенд, _, _ = М._збірка(вхід)
    тіла = [("стенд", стенд)] + [(ім, ПС.тіло(зр, обх)) for ім, зр, обх in (
        ("пісочний", 168, dict(плечі=98, груди=92, талія=72, стегна=100)),
        ("яблуко", 160, dict(плечі=104, груди=104, талія=88, стегна=112)),
        ("трикутник", 170, dict(плечі=100, груди=96, талія=84, стегна=104)))]
    прикраси = [р for р in каталог if р.get("слот") in АК.ЛАНЦЮГОВІ_СЛОТИ
                and р.get("ланцюг_см") is not None]
    верхи = [р for р in каталог if р.get("слот") in ("верх", "сукня", "комплект")
             and (р.get("виріз_тип") in АК.ГЛИБИНИ_ВИРІЗУ
                  or (р.get("край_джерело") == "річ" and р.get("верх_см") is not None))]
    результат = dict(каталог=[len(каталог), len(прикраси), len(верхи)], тіла={})
    print("каталог / кольє / горловини:", результат["каталог"])
    for назва, тіло in тіла:
        пари, лічба, приклад = {}, collections.Counter(), None
        for п in прикраси:
            for в in верхи:
                знахідки = АК.кольє_проти_горловини(тіло, [п, в])
                підпис = [[з["правило"], з["сила"], з["сила_нп"]] for з in знахідки]
                пари[f"{п['id']} × {в['id']}"] = підпис
                лічба[json.dumps(підпис, ensure_ascii=False)] += 1
                if приклад is None and знахідки:
                    приклад = dict(кольє=п["id"], верх=в["id"],
                                   пояснення=знахідки[0].get("чому"), знахідка=знахідки[0])
        результат["тіла"][назва] = dict(пари=пари, приклад=приклад)
        print(назва, "пар", len(пари), "вердикти", dict(лічба))
    with gzip.open(вихід, "wt", encoding="utf-8") as ф:
        json.dump(результат, ф, ensure_ascii=False)


if __name__ == "__main__":
    арг = argparse.ArgumentParser(description=__doc__)
    арг.add_argument("--вихід", type=Path)
    арг.add_argument("--звірити", nargs=2)
    опції = арг.parse_args()
    if опції.звірити:
        звірити(*опції.звірити)
    else:
        if опції.вихід is None:
            арг.error("потрібен --вихід або --звірити")
        вимір(опції.вихід.resolve())
