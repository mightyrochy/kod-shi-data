"""Лічба Ч4: (1) запити повтору до мосту проти записаних — скільки байт у байт, де перша розбіжність;
(2) файл вердиктів сторінки проти файла вердиктів повтору — рука, склад, текст; (3) знімки CPython / Pyodide — sha256.
  python3 -I порівняти.py <тека роботи, напр. /tmp/ч4> > результат.json"""
import glob, hashlib, json, os, sys

W = sys.argv[1]
D = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
вих = {}
for с in ('с5_весілля_сестри', 'с8_мінус_десять_сніг'):
    р = {}
    записи = [json.loads(х) for х in open(os.path.join(D, 'стенд/службове', с, 'обміни.jsonl'), encoding='utf-8') if х.strip()]
    повтор = [json.loads(х) for х in open(os.path.join(W, 'вих/стенд/службове', с, 'обміни.jsonl'), encoding='utf-8') if х.strip()]
    р['записаних_викликів_моста'] = len(записи)
    р['викликів_моста_в_повторі'] = len(повтор)
    р['байт_у_байт'] = sum(1 for х in повтор if х.get('точно'))
    р['виклики'] = [{'виклик': х.get('виклик'), 'запис': х.get('запис'), 'точно': х.get('точно'),
                     'спільний_префікс': х.get('спільний_префікс'), 'довжина': х.get('довжина'),
                     'довжина_запису': х.get('довжина_запису'), 'помилка': х.get('помилка'),
                     'розбіжність': х.get('розбіжність')} for х in повтор]
    п = json.load(open(os.path.join(W, 'вих', с, 'підсумок.json'), encoding='utf-8'))
    о = json.load(open(os.path.join(D, с, 'підсумок.json'), encoding='utf-8'))
    р['кроків_лягло'] = {'сторінка': о.get('кроків_лягло'), 'повтор': п.get('кроків_лягло'), 'джерела': п.get('кроків_джерела')}
    р['слів_лягло'] = {'сторінка': о.get('слів_лягло'), 'повтор': п.get('слів_лягло')}
    р['мережа_повтору'] = п.get('мережа')
    р['невзяті_записи'] = п.get('невзяті')

    def вердикти(шлях):
        if not шлях:
            return None
        д = json.load(open(шлях, encoding='utf-8'))
        return [{'рука': в.get('рука'), 'позиція': в.get('позиція'), 'склад': в.get('склад'),
                 'рука_впала': в.get('рука_впала'), 'ітерацій': в.get('ітерацій'),
                 'текст_sha': hashlib.sha256(str(в.get('текст')).encode()).hexdigest()[:12]}
                for пр in д['прогони'] for в in пр['вердикти']]
    сторінка = sorted(glob.glob(os.path.join(D, с, 'verdykty-*.json')))
    свій = sorted(glob.glob(os.path.join(W, 'вих', с, 'verdykty-*.json')))
    р['вердикти_сторінки'] = вердикти(сторінка[-1] if сторінка else None)
    р['вердикти_повтору'] = вердикти(свій[-1] if свій else None)
    зн = {}
    for ім in ('pyo_сторінка', 'pyo_node', 'cpy'):
        ш = os.path.join(W, 'зн', f'{с}_{ім}.jsonl')
        if os.path.exists(ш):
            б = open(ш, 'rb').read()
            зн[ім] = {'sha256': hashlib.sha256(б).hexdigest(), 'викликів': б.count(b'\n') - 1}
    р['знімки'] = зн
    вих[с] = р
json.dump(вих, sys.stdout, ensure_ascii=False, indent=1)
