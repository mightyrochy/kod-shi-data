# -*- coding: utf-8 -*-
"""Е3-одна-величина ч21 (п.7, точка речі): довжини й краї речей фіду на тілах стенда ДО → ПІСЛЯ.

Запуск із кореня репозиторію:
    python3 аудит/проби/Е3_ч21_точка_речі.py                       # ПІСЛЯ: код цієї гілки
    git worktree add /tmp/до <SHA_ДО>
    python3 аудит/проби/Е3_ч21_точка_речі.py --код /tmp/до/джерела  # ДО: той самий скрипт на старому коді

Каталог — `джерела/каталог_повний.xml` цього клону через живий `bridge.виклик("запити")` стенда (як
`Е3_ч16_каталог.py`); модель і платні API не викликаються. Друкує:
  · довжину виробу з фіду: (слот, рівень точки, розкид) — розкид «None» = «невідомо»;
  · клас довжини зі слова (`довжина_рівень`, джерело param/назва) і халяву взуття за типом — для звірки, що їх не
    зачеплено;
  · краї речей з довжиною на тілах 155/165/175 см (обхвати стенда): джерело краю, похибка краю `fit.похибка_краю`
    (відома / «невідомо»), надлишок довжини, вузол «край» графа (смуга для моделі чи нема);
  · K-FIT-03: `fit.довжина_проти_зросту` і `fit.краї` за (сила, заява) на тих самих речах."""
import sys, pathlib, json, collections, os, io, contextlib

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
код = pathlib.Path(sys.argv[sys.argv.index("--код") + 1]).resolve() if "--код" in sys.argv else КОРІНЬ / "джерела"
os.chdir(код); sys.path.insert(0, str(код))
import feed as Ф, bridge as B, composer as КМ, fit as ПС, graph as Г

вх = json.load(open(код / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску(str(КОРІНЬ / "джерела" / "каталог_повний.xml")); вх["гілка"] = 0
with contextlib.redirect_stdout(io.StringIO()):
    json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
print(f"код: {код}  · речей каталогу {len(кат)}")


def друк(назва, л, n=40):
    print(f"{назва}:")
    for к, v in sorted(л.items(), key=lambda x: (-x[1], str(x[0])))[:n]:
        print(f"   {v:6d}  {к}")


з_довжиною = [c for c in кат if c.get("довжина_виробу_см") is not None]
друк(f"довжина виробу: речей {len(з_довжиною)} — (слот, рівень точки, розкид см)", collections.Counter(
    (c.get("слот"), c.get("довжина_виробу_точка"), c.get("довжина_виробу_розкид_см")) for c in з_довжиною), 30)
друк("довжина виробу — за чим (назва параметра чи опис) × рівень × розкид відомий", collections.Counter(
    ((c.get("довжина_виробу_за_чим") or "").split("=")[0].split("«")[1][:40] if "«" in (c.get("довжина_виробу_за_чим") or "")
     else c.get("довжина_виробу_за_чим"), c.get("довжина_виробу_точка"), c.get("довжина_виробу_розкид_см") is not None)
    for c in з_довжиною), 25)
друк("клас довжини зі слова (слот, клас, джерело)", collections.Counter(
    (c.get("слот"), c.get("довжина_рівень"), (c.get("довжина_джерело") or "")[:14]) for c in кат
    if c.get("довжина_рівень")), 25)
друк("халява взуття (рівень, джерело)", collections.Counter(
    (c.get("халява_рівень"), c.get("халява_джерело")) for c in кат if c.get("слот") == "взуття"), 15)

ОБХВАТИ = dict(плечі=98, груди=92, талія=74, стегна=100)
краї, k03, k03к, вузли = collections.Counter(), collections.Counter(), collections.Counter(), collections.Counter()


def ключ(z):
    return (z["правило"], z["сила"], tuple(sorted(з["code"] for з in (z.get("заяви") or []))))


# Похибки рівнів тіла стенд поки не несе (`fit.тіло`: `похибка_висот` — None, частина ч14/ч16), тож похибка краю —
# «невідомо» на всіх речах і ДО, і ПІСЛЯ. Для показу — те саме тіло з похибкою рівнів із запису реєстру (1 SD частки
# зросту × зріст; не продукт): тоді видно, що похибку краю дає саме точка виміру.
import похибка_вимірів_тіла as ПВТ
пок = collections.Counter()
for зр in (155, 165, 175):
    t = ПС.тіло(зр, ОБХВАТИ)
    t["похибка_висот"] = {н: (None if ПВТ.похибка("рівень", н) is None else ПВТ.похибка("рівень", н) * зр)
                          for н in t["похибка_висот"]}
    with contextlib.redirect_stdout(io.StringIO()):
        for c in з_довжиною:
            if c.get("слот") in ("низ", "сукня", "комплект", "верхній_шар", "верх"):
                р = КМ.у_річ(dict(c), c["слот"], t)
                if р:
                    пк = ПС.похибка_краю(t, р)
                    пок[(зр, "похибка краю відома" if пк is not None else "похибка краю невідома",
                         "до 5 см" if пк is not None and пк <= 5 else "5–10 см" if пк is not None and пк <= 10
                         else "понад 10 см" if пк is not None else "",
                         "надлишок понад похибку" if р.get("довжина_надлишок_см") is not None else "")] += 1

for зр in (155, 165, 175):
    t = ПС.тіло(зр, ОБХВАТИ)
    with contextlib.redirect_stdout(io.StringIO()):
        речі = [КМ.у_річ(dict(c), c["слот"], t) for c in з_довжиною
                if c.get("слот") in ("низ", "сукня", "комплект", "верхній_шар", "верх")]
    речі = [р for р in речі if р]
    for р in речі:
        пк = ПС.похибка_краю(t, р)
        краї[(зр, р.get("край_джерело"), "похибка краю відома" if пк is not None else "похибка краю невідома",
              "надлишок" if р.get("довжина_надлишок_см") is not None else "")] += 1
        вузли[(зр, р.get("край_джерело"), "край у графі" if "край" in Г.зона(р) else "краю нема")] += 1
    for z in ПС.довжина_проти_зросту(t, речі):
        k03[(зр,) + ключ(z)] += 1
    for р in речі:
        with contextlib.redirect_stdout(io.StringIO()):
            for z in ПС.краї(t, [р]):
                k03к[(зр,) + ключ(z)] += 1
друк("краї речей з довжиною: (зріст, джерело краю, похибка краю, надлишок)", краї)
друк("ПОКАЗ (не продукт): тіло з похибкою рівнів реєстру — (зріст, похибка краю, величина, надлишок)", пок)
друк("вузол «край» графа (смуга для моделі): (зріст, джерело, є)", вузли)
друк("K-FIT-03 довжина_проти_зросту: (зріст, правило, сила, заяви)", k03)
друк("K-FIT-03 fit.краї по одній речі: (зріст, правило, сила, заяви)", k03к)
