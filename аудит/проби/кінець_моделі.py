"""Позначає кінець фаз автоживого з моделлю: обгортка відпускає замок GPU до кінця прогону.

Адресу позначки обгортка дає змінною KINETS_MODELI процесові GPU-наряду (`queue_lanes.ps1`, Set-ModelPhaseMark);
процес наряду бачить файл на найближчому такті очікування й відпускає оренду карти (Exit-GpuModelPhase), а
`записати_сцену.py` після позначки сцен не пише. Без змінної (ручний наряд, наряд без GPU) нічого не пише:
замок, якщо його взято, обгортка тримає до кінця прогону.
"""
from datetime import datetime, timezone
import os
from pathlib import Path


def виконати():
    """Пише позначку з часом UTC і друкує факт; 1 — позначку записати не вдалося (замок лишається до кінця)."""
    шлях = os.environ.get("KINETS_MODELI", "")
    if not шлях:
        print("KINETS_MODELI нема: замок GPU, якщо його взято, обгортка тримає до кінця прогону")
        return 0
    час = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    try:
        Path(шлях).write_text(час + "\n", encoding="utf-8")
    except OSError as збій:
        print("позначку кінця фаз з моделлю не записано (%s): %s; замок GPU лишається до кінця прогону" % (шлях, збій))
        return 1
    print("кінець фаз з моделлю позначено о %s (%s): обгортка відпускає замок GPU, сцен далі прилад не пише" % (час, шлях))
    return 0


if __name__ == "__main__":
    raise SystemExit(виконати())
