"""Друкує факти на справжніх модулях жниварки й чистки; це окремий обсяг, не повний корпус."""
import importlib
import json
from pathlib import Path
import sys


def головна():
    """Перевіряє дві вставки та читача назви без зміни продуктового дерева."""
    sys.path.insert(0, str(Path('джерела/прилади').resolve()))
    п = importlib.import_module('корінь_річ_запис_речі')
    файл = 'zhnyvarka/жниварка.py'
    код = Path(файл).read_text(encoding='utf8')
    маркер = '    if (not ф["опис"] or російське(ф["опис"])) and блок_опису is not None:'
    вставка = '    ф["проба_а"] = суп.get_text(" ")[:50]\n    ф["проба_б"] = bool(re.search(r"розпродано", суп.get_text(" ")))\n'
    п4 = []
    for текст in (код, код.replace(маркер, вставка + маркер, 1)):
        п._ПІДВИРАЗИ.clear()
        а = п.Аналіз([п.розібрати_py(файл, текст)], п.Реєстр('.'))
        а.пройти()
        п4.append(sorted(р for (_, р, пункт) in п.обчислити(а) if пункт == 4))
    файли = ('feed', 'фід_розбір', 'покроковик', 'назва_речі', 'чистка_каталогу', 'фід_каталог')
    п._ПІДВИРАЗИ.clear()
    модулі = [п.розібрати_py('джерела/' + ф + '.py', Path('джерела/' + ф + '.py').read_text(encoding='utf8')) for ф in файли]
    модулі.append(п.розібрати_py('джерела/вхід.py', "import чистка_каталогу\nчистка_каталогу.почистити('каталог_повний.xml','каталог_повний.xml')\n"))
    а = п.Аналіз(модулі, п.Реєстр('.'))
    а.пройти()
    функція = next(ф for ф in а.функції if ф.mod == 'чистка_каталогу' and ф.name == 'почистити')
    межа = max(оп.line for оп in функція.stmts)
    п3 = sorted(р for (ф, р, пункт) in п.обчислити(а) if ф == функція.file and функція.line <= р <= межа and пункт == 3)
    print(json.dumps(dict(обсяг='жниварка окремо; шість модулів чистки зі входом відомого каталогу', п4_ДО=п4[0], п4_ПІСЛЯ=п4[1], приріст_п4=len(п4[1]) - len(п4[0]), чистка_п3=п3), ensure_ascii=False))
    return int(len(п4[1]) - len(п4[0]) != 2 or not п3)


if __name__ == '__main__':
    sys.exit(головна())
