# -*- coding: utf-8 -*-
"""Зводить часові позначки приладу в таблиці без подвійного додавання часу сцен."""
from collections import defaultdict
from datetime import datetime
import json
from pathlib import Path
from statistics import median


ТУТ = Path(__file__).resolve().parent


def події(файл):
    return [json.loads(р[4:]) for р in файл.read_text(encoding='utf-8').splitlines() if р.startswith('ЧАС ')]


def виконати():
    дані = json.loads((ТУТ / 'вимір.json').read_text(encoding='utf-8'))
    запуски = дані['запуски']
    повні = [р for р in запуски if р['назва'].startswith('повний-')]
    тривалості = []
    сцени = []
    for запуск in повні:
        журнал = події(ТУТ / (запуск['назва'] + '.log'))
        тривалості.extend(dict(запуск=запуск['назва'], **п) for п in журнал if п['подія'] == 'кінець')
        сцени.extend(dict(запуск=запуск['назва'], **п) for п in журнал if п['подія'] == 'кінець сцени')
        if запуск.get('таймаут') or запуск.get('перервано'):
            останній = next(п for п in reversed(журнал) if п['подія'] == 'початок')
            секунд = (datetime.fromisoformat(запуск['кінець']) - datetime.fromisoformat(останній['utc'])).total_seconds()
            тривалості.append(dict(запуск=запуск['назва'], сцена=останній['сцена'],
                                    етап=останній['етап'] + ' (перервано, частковий час)', секунд=секунд))
    if not повні:
        raise ValueError('Повний вимір ще не закінчився')
    разом = sum(р['секунд'] for р in повні)
    сума = sum(п['секунд'] for п in тривалості)
    розбіжність = abs(разом - сума) / разом * 100
    етапи = defaultdict(float)
    for п in тривалості:
        етапи[п['етап']] += п['секунд']
    найдовший, секунд = max(етапи.items(), key=lambda п: п[1])
    частка = секунд / разом * 100
    повно = len(сцени) == дані['записів']
    середнє = sum(п['секунд'] for п in сцени) / len(сцени)
    до_розриву = [п for п in сцени if п['utc'] < '2026-11-19T11:31:55Z']
    середнє_до = sum(п['секунд'] for п in до_розриву) / len(до_розриву)
    стенди = [п for п in тривалості if п['етап'] == 'стенд на записаних відповідях']
    пояснення = (f'Таймер етапу «{найдовший}» дав {секунд:.3f} с ({частка:.2f}% сирого часу, включно з розривом). '
                 f'Для прогнозу використано тільки {len(до_розриву)} завершених сцен до розриву: {середнє_до:.3f} с на сцену; '
                 f'лінійна оцінка 54 записів за цим складом — {середнє_до * 54:.3f} с '
                 f'({середнє_до * 54 / 60:.2f} хв). '
                 f'Оцінка решти {дані["записів"] - len(сцени)} наявних записів — '
                 f'{середнє_до * (дані["записів"] - len(сцени)):.3f} с; переносити цей середній склад на невиміряні сцени можна лише як гіпотезу.')
    підсумок = {'повний': повно, 'записів': len(сцени), 'секунд': разом,
                'сума_етапів': сума, 'розбіжність_відсотків': розбіжність,
                'етапи': dict(етапи), 'записів_для_оцінки': len(до_розриву), 'секунд_на_запис': середнє_до,
                'сире_середнє_з_розривом': середнє,
                'оцінка_54_секунд': середнє_до * 54,
                'оцінка_решти_секунд': середнє_до * (дані['записів'] - len(сцени))}
    (ТУТ / 'підсумок.json').write_text(json.dumps(підсумок, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    рядки = [
        '# Час приладу нової бази на записах 04911e68', '',
        ('причина: ' if повно else f'гіпотеза: не завершено {дані["записів"] - len(сцени)} з {дані["записів"]} записів; активний час і паузу в розриві спостереження не розділено; ') + пояснення, '',
        f'Виміряно {len(сцени)}/{дані["записів"]} доступних записів. Загальний час процесів Node — {разом:.3f} с; '
        f'сума неперекривних етапів — {сума:.3f} с; розбіжність — {розбіжність:.3f}% (мірило ≤5%).', '',
        'Вхід — усі теки з `повтор.json` і `результат.json` у врятованому прогоні: 51 на верхньому рівні '
        'та два записи у `повтор_середовища/`. Число 54 у наряді не відповідає збереженому дереву: '
        'фактично є 53 записи. Це 51 різний id та два повтори. Маніфест і SHA-256 усіх вхідних файлів — `вимір.json`.', '',
        'Команда приладу для кожного батьківського каталогу — `node аудит/проби/нова_база.js <копія записів> --main origin/main`. '
        'Обгортка `виміряти.py` завантажує той самий CommonJS-модуль і викликає його експорт `виконати` з цими аргументами. '
        'Копії розташовано в `$TEMP/base-time-measure/` у теці задачі: прилад переносить записи, тож оригінали не запускалися на перенос. '
        'Вкладені записи планувалось виміряти окремо, бо прилад читає тільки безпосередні дочірні теки; '
        'до їхнього запуску через перевищення межі часу не дійшло. '
        'Вхідні файли до й після ' + ('побайтово однакові.' if дані.get('вхід_незмінний') else 'ще не звірено.'), '',
        'Межа трьох годин перевищена під час розриву спостереження. Останній успішний контроль інструмента — '
        '11:31:55Z, наступний — 15:20:50Z; між ними інструмент повернув gRPC timeout та повідомив про заміну runtime. '
        'Після відновлення доступу прохід зупинено деревом власного процесу Node; кінець обліку — 15:21:12Z. '
        '`ж1_побачення_можливо_дощ` має 13826,598 с монотонного часу; причина розриву, '
        'час неспання та активна робота процесу всередині нього не виміряні. '
        'Сума таймерів у таблиці включає цей інтервал і не є виміром часу неспання. '
        'Місце примусового зняття — `ж1_робота`, етап «стенд на записаних відповідях»; '
        'його частковий час додано до таблиці за UTC до зняття.', '',
        f'На початку `origin/main` вказував на `{дані["main"]}`. '
        f'Після розриву він уже вказував на `{дані["main_після_виміру"]["sha"]}`: '
        'Git-сховище спільне, посилання оновлювалось зовні. Початковий запуск передавав саме '
        '`--main origin/main`, тому незмінність цієї адреси для кожної сцени не доведено. '
        'Остаточну звірку рішень проведено з початковим повним SHA як `--main`, щоб обидві версії '
        'одержували тотожний вхід. Попередні 5/5 однакових звірок на плаваючому посиланні '
        'збережено в `порівняння-origin-main.zip`. Показ — готова збірка штампа '
        '`04911e686195fc47873b70a231d6b70876f83af2` зі шляху `команда` в `результат.json`, '
        'кеш — `C:\\Users\\gemini\\pyodide`; `NODE_PATH=C:\\Users\\gemini\\kod-shi-test-node\\node_modules`. '
        'Модель не викликається: `середовищеСцени` встановлює `REPLAY_EXCHANGE`, стенд бере відповіді з записаного обміну.', '',
        'Прилад не збирає показ штампа: він тільки перевіряє готовий `index.html` і кеш. '
        'Тому збирання всередині приладу — 0 с, а перевірка наявності показу виділена окремим етапом. '
        'Повторного збирання на кожну сцену тут немає; часові позначки не змінюють рішення, таймаут чи порядок сцен.', '',
        'Перерваний попередній хід залишив завершений лог `ПІСЛЯ-ж7_збій_правил_без_підборів`, '
        'але не записав час зовнішнього процесу у `вимір.json`. Його файли збережено з суфіксом '
        '`-попередній-хід`; цей запуск не включено до таблиць. Сцену повторено до завершення з обліком часу.', '',
        '| Етап | Секунд | Частка загального часу |', '|---|---:|---:|',
    ]
    рядки.extend(f'| {етап} | {час:.6f} | {час / разом * 100:.3f}% |' for етап, час in sorted(етапи.items(), key=lambda п: -п[1]))
    if стенди:
        часи = [п['секунд'] for п in стенди]
        рядки.extend(['', f'Завершених етапів стенда: {len(стенди)}; мінімум {min(часи):.3f} с, '
                       f'медіана {median(часи):.3f} с, максимум {max(часи):.3f} с. '
                       'Загальна тривалість складається з послідовних запусків, а не з одного спільного збирання показу.'])
    до_розриву = [п for п in сцени if п['utc'] < '2026-11-19T11:31:55Z']
    середнє_до = sum(п['секунд'] for п in до_розриву) / len(до_розриву)
    рядки.extend(['', f'Окремо, {len(до_розриву)} завершених сцен до розриву: середнє {середнє_до:.3f} с, '
                   f'лінійна оцінка 54 сцен — {середнє_до * 54:.3f} с ({середнє_до * 54 / 60:.2f} хв), '
                   f'решти {дані["записів"] - len(сцени)} незавершених — {середнє_до * (дані["записів"] - len(сцени)):.3f} с. '
                   'Це гіпотеза за початковим складом набору; пізніші сцени не виміряно.'])
    рядки.extend(['', 'П’ять тих самих сцен ДО → ПІСЛЯ додавання часових позначок. Це час окремого процесу Node, '
                   'разом із читанням баз main; прискорення не заявляється. «Рядки однакові» стосується двох фактичних браузерних запусків.', '',
                   '| Сцена | ДО, с | ПІСЛЯ, с | Рядки однакові |', '|---|---:|---:|---|'])
    for назва, однаково in дані['порівняння_фактичних_рішень'].items():
        до = next(р for р in запуски if р['назва'] == 'ДО-' + назва)
        після = next(р for р in запуски if р['назва'] == 'ПІСЛЯ-' + назва)
        рядки.append(f'| {назва} | {до["секунд"]:.3f} | {після["секунд"]:.3f} | {"так" if однаково else "ні"} |')
    різні = [с for с, однаково in дані['порівняння_фактичних_рішень'].items() if not однаково]
    рядки.extend(['', 'Різні фактичні виходи браузерних повторів: ' + (', '.join('`' + с + '`' for с in різні) or 'немає') + '. '
                   'Зокрема, `ж4_весілля_гостя`: ДО — взято 5/6, невзято `00005.json`, rc=2; ПІСЛЯ — повне відтворення, rc=0. '
                   'Незалежні браузерні повтори не доводять рівності рішень. Початкові результати не вилучено й не підмінено. '
                   'Правила приладу від різних виходів стенда відокремлено наступною звіркою.', ''])
    рядки.extend(['Виходи `ж3_кафе_20` та `ж4_весілля_гостя`, які попередній хід не захопив у gzip, '
                   'збережено окремим коротким запуском `дозняти_виходи.py`. Це збір доказів для звірки правил, '
                   'його час не додано до часткового повного проходу.', ''])
    тотожні = json.loads((ТУТ / 'тотожні_рішення.json').read_text(encoding='utf-8'))
    assert len(тотожні) == 5 and all(р['однаково'] and р['main'] == дані['main'] for р in тотожні)
    рядки.extend(['ДО й ПІСЛЯ на тотожному збереженому виході стенда (`звірити_рішення.py`; '
                   'походження кожного виходу та SHA-256 — `тотожний-стенд-джерела.json`). '
                   'Використано справжні записи тих самих п’яти сцен; браузер удруге не запускався. '
                   'Ці часи перевіряють лише правила приладу та запис бази; вони не є виміром прискорення стенда.', '',
                   '| Сцена | ДО, с | ПІСЛЯ, с | rc та рядки `НОВА_БАЗА.md` однакові |', '|---|---:|---:|---|'])
    for р in тотожні:
        рядки.append(f'| {р["сцена"]} | {р["запуски"][0]["секунд"]:.3f} | {р["запуски"][1]["секунд"]:.3f} | {"так" if р["однаково"] else "ні"} |')
    рядки.extend(['',
                   'Повна таблиця етапів (часи сцен окремо до суми не додаються):', '',
                   '| Запуск / сцена | Етап | Секунд |', '|---|---|---:|'])
    рядки.extend(f'| {п["запуск"]} / {п["сцена"]} | {п["етап"]} | {п["секунд"]:.6f} |' for п in тривалості)
    створені = sorted({'/'.join(ф.replace('\\', '/').split('/')[:5])
                      for р in запуски for ф in р.get('створено_нічних_файлів', [])})
    рядки.extend(['', 'Створені й прибрані теки нічної бази:', ''])
    рядки.extend('- `' + ф + '`' for ф in створені)
    завершені = set()
    for п in сцени:
        запуск = next(р for р in повні if р['назва'] == п['запуск'])
        завершені.update(ф.replace('\\', '/') for ф in запуск['сцени'] if Path(ф).name == п['сцена'])
    усі = {str(Path(ф).parent).replace('\\', '/') for ф in дані['вхідні_файли']
           if Path(ф).name == 'повтор.json'}
    рядки.extend(['', 'Не завершені записи (перерваний `ж1_робота` включено):', ''])
    рядки.extend('- `' + ф + '`' for ф in sorted(усі - завершені))
    рядки.extend(['', 'Створені приладом нічні файли після кожного запуску видалено. Перелік шляхів — '
                   '`створено_нічних_файлів` у `вимір.json`; нічних баз у цьому PR немає. '
                   'Жодного файлу врятованого запису, стенда, приймання, продукту, CI чи адаптера не змінено.', '',
                   'Перевірки: синтаксис Node, `git diff --check` та згортання дошки — коди в `перевірки.json`. '
                   'Штатна `перевірити_нову_базу.js` на початковому й зміненому коді аварійно завершує Node '
                   'кодом Windows `3221226505` (`0xC0000409`) на `fs.cpSync` фікстури, до перевірок приладу '
                   '(`діагностика.log`). Допоміжний запуск із копіюванням через Python проходить далі та '
                   'знаходить платформну розбіжність `\\` проти `/` у перевірці шляху на рядку 91 '
                   '(`перевірка-копії-після.log`); зеленою штатну перевірку не названо.', '',
                   'Не виміряно: точний розподіл ≈129 хв неспання незавершеного запуску 18.11 — в його лозі '
                   'немає часових позначок. Поточні часи не відновлюють історичне навантаження Chrome, диска, '
                   'паузи живлення або стан ноутбука. Оцінка для 54 сцен переносить середній склад виміряного набору, '
                   'а не доводить однакову тривалість різних сценаріїв.', ''])
    (ТУТ / 'ЗВІТ.md').write_text('\n'.join(рядки), encoding='utf-8')
    корінь = ТУТ.parents[2]
    джерело = next(р for р in (корінь / 'аудит/БЕКЛОГ.md').read_text(encoding='utf-8').splitlines()
                   if р.startswith('| 16675 |'))
    клітинки = джерело.split('|')
    клітинки[2] += (f' вимір 19.11: пройдено {len(сцени)}/{дані["записів"]} наявних записів '
                    f'за {разом:.3f} с сирого часу, включно з невиміряним розривом спостереження 11:31–15:20Z; '
                    f'гіпотеза за {len(до_розриву)} сценами до розриву — {середнє_до:.3f} с на сцену; '
                    f'таймер етапу «{найдовший}» — {частка:.2f}% сирого часу; '
                    f'розбіжність суми етапів і часу процесів {розбіжність:.3f}%; '
                    f'незалежні браузерні повтори дали різні виходи у {len(різні)}/5 пар. ')
