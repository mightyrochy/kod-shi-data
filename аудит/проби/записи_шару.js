/* Ключ заяви й місце повідомлення належать різним мапам журналу. */
function джерелоШару(запис, ключ){
  if (запис.напрям !== 'out_messages') return (запис.вхід || {})[ключ];
  const рядок = (запис.заяви || запис.розмітка || []).find(р => р.ключ === ключ);
  return рядок ? {kind: рядок.вид, statements: рядок.заяви} : undefined;
}

/* Напис інтерфейсу в полі виходу не є перекладом пропущеної заяви. */
function перекладШару(запис, ключ){
  if (запис.напрям !== 'out_messages') return (запис.вихід || {})[ключ];
  const рядок = (запис.заяви || []).find(р => р.ключ === ключ && р.стан === 'translated');
  return рядок && рядок.текст;
}

/* Типово рахує лише переклади всіх заяв питання. Режим доставки окремо враховує
   текст відповіді, який пізніше відхилив мовний сторож; запасний напис не є відповіддю. */
function питаньЗВідповіддю(записи, потрібенПереклад=true){
  const питання = new Map();
  for (const з of (записи || []).filter(з => з.напрям === 'out_messages' && /code_unknowns/.test(з.де || ''))){
    for (const р of з.заяви || []){
      if (!/^питання\./.test(р.повідомлення)) continue;
      if (!питання.has(р.повідомлення)) питання.set(р.повідомлення, new Map());
      const заяви = питання.get(р.повідомлення);
      const прийнято = р.стан === 'translated' || (!потрібенПереклад
        && ['foreign_language', 'latin_remainder'].includes(р.стан));
      заяви.set(р.ключ, заяви.get(р.ключ) || (прийнято && !!р.текст));
    }
  }
  return [...питання.values()].filter(з => [...з.values()].every(Boolean)).length;
}

module.exports = {джерелоШару, перекладШару, питаньЗВідповіддю};
