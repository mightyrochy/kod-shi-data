"""Ізолює три причини в тимчасових копіях palettes; перевіряє бриф побайтно.

python аудит/проби/кольори_2028_3_причини.py <тека-доказів>
Справжній міст записує аргументи й сирі палітри. Повтор використовує ці самі
входи конструктора; жодного очікуваного виходу в досліди не підставляє.
"""
import copy
import gzip
import hashlib
import importlib.util
import json
import pathlib
import sys
import tempfile
from collections import Counter

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРІНЬ / "джерела"))
import palettes as П


def байти(значення):
    """Серіалізує бриф зі сталими порядком і пробілами, без втрати полів."""
    return json.dumps(значення, ensure_ascii=False, separators=(",", ":")).encode()


def дослід(текст, а, б, в):
    """Вимикає рівно названі причини, не змінюючи пороги чи генератор."""
    if not а:
        текст = текст.replace('[кінцевий_колір(к) for к in П["кольори"]]', 'П["кольори"]')
        текст = текст.replace('[кінцевий_колір(c) for c in П["кольори"]]', 'П["кольори"]')
    поч = текст.index('    # Вибір гами передує добору:')
    кін = текст.index('    h_шк = ', поч)
    блок = '    множ = НАСИЧЕНІСТЬ.get(насиченість or "середні", 1.0)\n'
    if б:
        if а:
            блок += '    П["кольори"] = [кінцевий_колір(к, множ) for к in П["кольори"]]\n'
        else:
            блок += '    if множ != 1.0:\n        П["кольори"] = [кінцевий_колір(к, множ) for к in П["кольори"]]\n'
        блок += '    if множ != 1.0:\n        for к in П["кольори"]:\n            ім, як = назва(к["lab"])\n            к.update(назва=ім, назва_як=як)\n'
    elif а:
        блок += '    П["кольори"] = [кінцевий_колір(к) for к in П["кольори"]]\n'
    блок += '    П["поєднання"] = поєднання(П, контраст_рівень, множ=' + ('множ' if б else '1.0') + ')\n'
    if not в:
        блок += '''    if множ != 1.0:
        кольори = П["кольори"] + [к for п in П["поєднання"] for к in п["кольори"]]
        for к in {id(к): к for к in кольори}.values():
            L, C, h = cs.lch(cs.hx(к["hex"]))
            if not C:
                continue
            lab = lab_з_lch(L, хрома_за_насиченістю(C, множ), h)
            hex = hex_з_lab(lab)
            lab = cs.hx(hex)
            L, C, h = cs.lch(lab)
            ім, як = назва(lab)
            к.update(L=L, C=C, h=h, lab=lab, hex=hex, назва=ім, назва_як=як)
'''
    return текст[:поч] + блок + текст[кін:]


def головна():
    """Записує контроль повтору, вимкнення причин і таблицю всіх 315 персон."""
    вихід = pathlib.Path(sys.argv[1]).resolve()
    вихід.mkdir(parents=True, exist_ok=True)
    читати = lambda п: json.loads(gzip.decompress(п.read_bytes()))
    до = читати(КОРІНЬ / 'аудит/перевірка/доробка_2028_2/ДО/середні-персони.json.gz')
    історія = читати(КОРІНЬ / 'аудит/перевірка/кольори_9858/доробка/персони.json.gz')
    мод = importlib.util.spec_from_file_location('вимір_9858', pathlib.Path(__file__).with_name('кольори_9858.py'))
    вимір = importlib.util.module_from_spec(мод)
    мод.loader.exec_module(вимір)
    текст = (КОРІНЬ / 'джерела/palettes.py').read_text(encoding='utf-8')
    режими = {'усе': (1, 1, 1), 'без_а': (0, 1, 1), 'без_б': (1, 0, 1),
              'без_в': (1, 1, 0), 'без_усіх': (0, 0, 0)}
    записи, підсумок = [], Counter()
    with tempfile.TemporaryDirectory(prefix='kolory-2028-3-') as тимчасова:
        модулі = {}
        for ім, перемикачі in режими.items():
            файл = pathlib.Path(тимчасова) / (ім + '.py')
            файл.write_text(дослід(текст, *перемикачі), encoding='utf-8')
            специфікація = importlib.util.spec_from_file_location('дослід_' + ім, файл)
            м = importlib.util.module_from_spec(специфікація)
            специфікація.loader.exec_module(м)
            модулі[ім] = м
        сирий, практична = П._палітра_практична, П.палітра_практична
        виклики, сирі = [], []
        def записати_сиру(*арг, **іменовані):
            """Фіксує сире джерело до трьох досліджуваних перетворень."""
            р = сирий(*арг, **іменовані)
            сирі.append(copy.deepcopy(р))
            return р
        def записати_практичну(*арг, **іменовані):
            """Фіксує аргументи справжнього конструктора з моста."""
            р = практична(*арг, **іменовані)
            виклики.append((copy.deepcopy(арг), copy.deepcopy(іменовані), copy.deepcopy(сирі[-1]), copy.deepcopy(р)))
            return р
        П._палітра_практична, П.палітра_практична = записати_сиру, записати_практичну
        try:
            for і, персона in enumerate(до):
                виклики.clear()
                сирі.clear()
                після = вимір.зняти(персона['вхід'])
                варіанти = {ім: [] for ім in режими}
                кеш = {}
                # Кожна гілка викликає практичну палітру; тотожність із мостом
                # перевіряється нижче для повної серіалізації, включно з порядком.
                for арг, іменовані, сира, готова in виклики:
                    for ім, м in модулі.items():
                        ключ = (ім, байти((арг, іменовані, сира)))
                        if ключ in кеш:
                            варіанти[ім].append(кеш[ключ])
                            continue
                        м._палітра_практична = lambda *а, **к: copy.deepcopy(сира)
                        р = м.палітра_практична(*арг, **іменовані)
                        кеш[ключ] = м.для_пакета(р)
                        варіанти[ім].append(кеш[ключ])
                assert байти(варіанти['усе']) == байти(після['бриф']), (і, 'повтор не відповідає мосту')
                assert байти(варіанти['без_усіх']) == байти(персона['бриф']), (і, 'після вимкнення причин лишилась зміна')
                короткий = lambda р: [г.get('поєднання') for г in р]
                змінено = байти(короткий(після['бриф'])) != байти(короткий(історія[і]['бриф_ДО']))
                причини = [літ for літ in ('а', 'б', 'в') if байти(варіанти['без_' + літ]) != байти(варіанти['усе'])]
                доповнена = історія[і]['раніше_без_аналогової']
                if доповнена:
                    причини.append('г: доповнення аналогової спільним джерелом до ДО 165bb913')
                if змінено:
                    assert причини, (і, 'непояснена зміна')
                підсумок['доповнених' if доповнена else 'решта'] += 1
                підсумок['доповнених_змінено' if доповнена else 'решта_змінено'] += змінено
                for літ in ('а', 'б', 'в'):
                    підсумок['вплив_' + літ] += літ in причини
                записи.append(dict(персона=і, вхід=персона['вхід'], доповнена=доповнена,
                                    короткий_бриф_змінено=змінено, причини=причини,
                                    sha256={ім: hashlib.sha256(байти(р)).hexdigest() for ім, р in варіанти.items()},
                                    брифи=варіанти))
                if (і + 1) % 5 == 0:
                    print(f'Причини: {і + 1}/315', flush=True)
        finally:
            П._палітра_практична, П.палітра_практична = сирий, практична
    assert підсумок['решта'] == 280 and підсумок['доповнених'] == 35
    (вихід / 'причини.json.gz').write_bytes(gzip.compress(байти(записи), mtime=0))
    результат = dict(підсумок, непояснених=0, повтор_моста=315, без_усіх_побайтно_ДО=315)
    (вихід / 'причини-вимір.json').write_text(json.dumps(результат, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(результат, ensure_ascii=False), flush=True)
    return 0


if __name__ == '__main__':
    sys.exit(головна())
