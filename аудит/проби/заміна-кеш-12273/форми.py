"""Друкує розбір усіх справжніх відповідей доповнення, включно з відхиленими."""
import json
from pathlib import Path
import sys


def перевірити():
    """Зберігає виняток неправильного outfits окремо від мірила кешу."""
    тека = Path(__file__).resolve().parent
    sys.path.insert(0, str(тека.parents[2] / 'джерела'))
    import заміна_речі
    запис = json.loads((тека / 'доповнення-32/обмін/00032.json').read_text(encoding='utf-8'))
    пул = json.loads(запис['запит']['messages'][-1]['content'][-1]['text'])['pool']['rows']
    номери = {р[0] for р in пул}
    звіт = []
    for ім in ('доповнення-32', 'доповнення-33', 'доповнення-33-повтор', 'доповнення-33-спроба-3'):
        р = json.loads((тека / ім / 'результат.json').read_text(encoding='utf-8'))
        рядок = {'проба': ім, 'текст': р['текст'], 'ключ': р['ключ']}
        try:
            номер, причина = заміна_речі._номер_відповіді(р['текст'], номери)
            рядок.update(номер=номер, причина=причина)
        except Exception as помилка:
            рядок['виняток'] = f'{type(помилка).__name__}: {помилка}'
        звіт.append(рядок)
    print(json.dumps(звіт, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    перевірити()
