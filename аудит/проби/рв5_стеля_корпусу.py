# -*- coding: utf-8 -*-
"""Проба РВ-5 · що насправді змінює друга стеля `_обмежити_корпусом` (Н-02-05, С-60).

Дві частини. (1) Для кожного рядка `реєстр_правил.ПОЛІТИКА_РЕГІСТРУ` із
`сила_корпусу` — виклик `_зн` тією силою, яку емітент СПРАВДІ передає (регексом
по коду модуля-емітента), і стрес-виклик силою `hard`; друкується, яка стеля
спрацювала (тір / корпус / жодна), кінцева сила, регістр, `блокує`.
(2) Шість сцен стенда через живий `bridge.запити` + `pipeline.перевірити_образ`
(той самий образ, що бере `стенд_знімок.образ_і_суд`): скільки знахідок несуть
`стеля_корпусу`, `стеля_тіру`, `гейт_знято`, і які саме правила.

Прогін:  cd джерела && python3 ../аудит/проби/рв5_стеля_корпусу.py
"""
import json, os, re, sys
ДЖ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "джерела")
sys.path.insert(0, os.path.abspath(ДЖ)); os.chdir(os.path.abspath(ДЖ))
import реєстр_правил as РП, accessory as А, outer as ВРХ, fit as ПС
import стенд_знімок as СЗ

РЕЄСТРИ = {"K-SHO": А.РЕЄСТР, "K-EYE": А.РЕЄСТР, "K-HAT": А.РЕЄСТР, "K-GLV": А.РЕЄСТР,
           "K-WEA": А.РЕЄСТР, "K-OUT": ВРХ.РЕЄСТР, "K-FIT": ПС.РЕЄСТР}
ЕМІТЕНТИ = {"K-SHO": "accessory.py", "K-EYE": "accessory.py", "K-HAT": "accessory.py",
            "K-GLV": "accessory.py", "K-WEA": "accessory.py", "K-OUT": "outer.py",
            "K-FIT": "fit.py", "K-KOH": "формальність.py", "K-PC-": "суд_образу.py",
            "профіль": "pipeline.py"}


def сили_емітента(правило):
    """Сили-літерали, з якими код кличе `_зн(правило, …)`; змінні не читаються."""
    ф = next((ф for п, ф in ЕМІТЕНТИ.items() if правило.startswith(п)), None)
    if not ф:
        return []
    т = open(ф, encoding="utf-8").read()
    return sorted(set(re.findall(r'_зн\(\s*"%s",\s*"(\w+)"' % re.escape(правило), т)))


print("── 1. ПОЛІТИКА: рядки зі стелею корпусу — виклик `_зн` силою емітента і силою hard")
print("   %-9s %-7s %-12s %-14s → %-8s %-8s %s" % ("правило", "корпус", "емітує", "виклик", "сила", "регістр", "стеля"))
for п, р in sorted(РП.ПОЛІТИКА_РЕГІСТРУ.items()):
    к = р.get("сила_корпусу")
    if not к:
        continue
    reg = next((v for пр, v in РЕЄСТРИ.items() if п.startswith(пр)), None)
    емітує = сили_емітента(п)
    for сила in sorted(set(емітує) | {"hard"}, key=lambda s: РП.ПОРЯДОК.index(s) if s in РП.ПОРЯДОК else 99):
        if сила in ("питання", "утримано", "ok"):
            continue
        з = РП._зн(п, сила, "суть", ["річ"], "чому", reg=reg)
        стеля = ("тір" if з.get("стеля_тіру") else "") + ("+корпус" if з.get("стеля_корпусу") else "")
        print("   %-9s %-7s %-12s %-14s → %-8s %-8s %s%s"
              % (п, к, ",".join(емітує) or "—", сила + (" (стрес)" if сила not in емітує else ""),
                 з["сила"], з["регістр"], стеля or "жодна",
                 "  гейт_знято" if "гейт_знято" in з else ""))

print("\n── 2. ШІСТЬ СЦЕН СТЕНДА: чиї стелі й зняті гейти доходять до виходу суду")
import bridge as B, pipeline as PL, composer as КМ, colorspace as cs
вх0 = json.load(open("стенд_вх.json", encoding="utf-8"))
разом = {"стеля_корпусу": {}, "стеля_тіру": {}, "гейт_знято": {}}
for назва, сцен in СЗ.СЦЕНАРІЇ.items():
    вх = dict(вх0, сценарій=сцен, випадок=назва)
    r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    к = r.get("кандидати") or {}
    _кат = {x.get("id"): x for x in B.каталог_останнього_пакета()}
    речі = []
    for слот in ("верх", "низ", "взуття", "сумка"):
        пул = к.get(слот) or []
        if пул:
            речі.append(dict(_кат.get(пул[0].get("id")) or пул[0], слот=слот))
    T = ПС.тіло(float(вх["зріст"]), {k: float(v) for k, v in вх["обхвати"].items()})
    F = cs.features(cs.hx(вх["шкіра"]), cs.hx(вх["волосся"][0]), cs.hx(вх["очі"]))
    готові = [КМ._у_річ(dict(c), c["слот"], T) for c in речі]
    вих = PL.перевірити_образ(F, готові, тіло=T, **сцен)
    з = [z for _, z in СЗ._знахідки_рекурсивно(вих)]
    лічба = {поле: sorted({z.get("правило") for z in з if z.get(поле)}) for поле in разом}
    for поле in разом:
        for пр in лічба[поле]:
            разом[поле][пр] = разом[поле].get(пр, 0) + 1
    print("   %-22s знахідок %2d · стеля_корпусу %s · стеля_тіру %s · гейт_знято %s"
          % (назва, len(з), лічба["стеля_корпусу"] or "—", lічба := лічба["стеля_тіру"] or "—",
             лічба["гейт_знято"] or "—"))
print("\n   разом по сценах (правило: у скількох сценах):")
for поле, d in разом.items():
    print("   %-15s %s" % (поле, d or "—"))
