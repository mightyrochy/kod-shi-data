"""Вето пулу й жорстке «ні» за словами типів, тканин і принтів на всьому каталозі — ДО і ПІСЛЯ одного читача
(корінь Е3-одна-величина, спроба 14; дошка 13630).

Запуск (модель і платні API не викликаються):
    python3 аудит/проби/Е3_вето_слова.py <корінь дерева> <каталог.pickle.gz> [<рішення.json.gz>]
Каталог — той самий pickle, що в `Е3_жорстке_ні_слова.py`. Слова — слова ядра переліків, якими мовний шар
кладе межі в `вето` (`мовний_шар.паспорт_з_шару`: типи — `item_type`, `feature`, `length`, `slot`; тканини —
`fabric`, `material`; принти — `pattern`) і класи `паспорт_основи.ВЕТО_СЛОВА`. Для кожного слова:
  · вето пулу — `пакет_моделі.жорстке_відсічення(r, вето={група: [слово]})` з причиною `person_veto`;
  · жорстке «ні» — `profile.жорстке_ні_фільтр` над списком, який з того самого паспорта складає
    `міст_вхід.застосувати_паспорт` цього дерева;
друкує, скільки пар (слово, річ) знімає лише один із двох (і скільки з «лише жорстке ні» пул знімає іншою
причиною), скільки знімає кожен і відбитки поіменних рішень.
"""
import gzip, hashlib, json, os, pickle, sys, warnings
from pathlib import Path


def головна():
    """Рішення обох читачів вето для кожного слова й кожної речі каталогу."""
    дерево, каталог_шлях = Path(sys.argv[1]).resolve(), sys.argv[2]
    os.chdir(дерево / "джерела")
    sys.path.insert(0, str(Path.cwd()))
    warnings.simplefilter("ignore")
    import profile as П, пакет_моделі as М, міст_вхід as МВ, внутрішня_мова as ВМ, паспорт_основи as ПО
    with gzip.open(каталог_шлях, "rb") as ф:
        каталог = pickle.load(ф)
    групи = dict(типи=("item_type", "feature", "length", "slot"), тканини=("fabric", "material"),
                 принти=("pattern",))
    слова = {}
    for група, переліки in групи.items():
        for перелік in переліки:
            for w in ВМ.ТАБЛИЦЯ[перелік].values():
                if isinstance(w, str) and w.strip() and w != "solid":
                    слова.setdefault((група, w.strip().lower()), None)
    for w in ПО.ВЕТО_СЛОВА:
        слова.setdefault(("принти" if w in ("смужка", "клітинка", "принт", "великий принт") else "типи", w), None)
    інша = {str(r.get("id")): М.жорстке_відсічення(r) for r in каталог}
    пул, ні, лише_пул, лише_ні, лише_ні_пул_інше = {}, {}, 0, 0, 0
    for група, w in слова:
        к = "%s:%s" % (група, w)
        список = МВ.застосувати_паспорт(dict(паспорт=dict(вето={група: [w]}, перекладено_шаром=True),
                                             сценарій={})).get("жорстке_ні") or []
        _, відкинуті = П.жорстке_ні_фільтр(каталог, список)
        ні[к] = sorted(str(в["id"]) for в in відкинуті)
        пул[к] = sorted(str(r.get("id")) for r in каталог
                        if (М.жорстке_відсічення(r, вето={група: [w]}) or "").startswith("person_veto"))
        лише_пул += len(set(пул[к]) - set(ні[к]))
        лн = set(ні[к]) - set(пул[к])
        лише_ні += len(лн)
        лише_ні_пул_інше += sum(1 for i in лн if інша.get(i))
    def відбиток(о):
        return hashlib.sha256(json.dumps(о, ensure_ascii=False, sort_keys=True).encode()).hexdigest()[:16]
    print(json.dumps(dict(
        речей=len(каталог), слів=len(слова),
        пар_лише_пул=лише_пул, пар_лише_жорстке_ні=лише_ні,
        з_них_пул_знімає_іншою_причиною=лише_ні_пул_інше,
        пар_пул=sum(map(len, пул.values())), пар_жорстке_ні=sum(map(len, ні.values())),
        слів_без_жодної_речі=sum(1 for к in пул if not пул[к] and not ні[к]),
        відбиток_пул=відбиток(пул), відбиток_ні=відбиток(ні)), ensure_ascii=False))
    if len(sys.argv) > 3:
        with gzip.open(sys.argv[3], "wt", encoding="utf-8") as ф:
            json.dump(dict(пул=пул, ні=ні), ф, ensure_ascii=False)
    return 0


if __name__ == "__main__":
    sys.exit(головна())
