def знахідки(x, вих):
    if isinstance(x, dict):
        if isinstance(x.get("правило"), str) and "сила" in x:
            вих.append((x["правило"], x.get("сила")))
        for v in x.values():
            знахідки(v, вих)
    elif isinstance(x, list):
        for v in x:
            знахідки(v, вих)
    return вих


