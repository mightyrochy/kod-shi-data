"""Порівнює межі шуму щік на всьому відтворюваному наборі й записаних рамках моделі.

Фото дістає сусідній `набір-портретів/збір.py`; тут вони лише читаються й звіряються за sha256.
Запуск із кореня: python -X utf8 аудит/проби/ворота-щік/вимір.py <тека фото сцен> <вихід.json>.
Залежності й PIP_DIR — як у `вимір-портрета-1211/вимір.py`; моделі й відеокарта не потрібні.
"""
import hashlib
import importlib.util
import itertools
import json
from pathlib import Path
import sys

ТУТ = Path(__file__).resolve().parent
НАБІР = ТУТ.parent / "набір-портретів"
МЕЖІ = (4, 5, 6, 8, 10, 12, 16)


def розбіжні(а, б):
    """Повертає класи, які обидва виміри стверджують по-різному; утримане твердження не порівнюється."""
    return {к: [а["класи"][к], б["класи"][к]] for к in а["класи"]
            if "не певна" not in (а["класи"][к], б["класи"][к]) and а["класи"][к] != б["класи"][к]}


def підсумок(рядки, межа, той_самий_кадр=False):
    """Лічить усі придатні кадри й пари однієї людини для заданої межі, окремо — повтори рамок того самого кадру."""
    пройшли = [р for р in рядки if р["стан_без_воріт_щік"] == "вимір" and р["шум"] <= межа]
    пари = []
    for а, б in itertools.combinations(пройшли, 2):
        if а["людина"] != б["людина"] or (а["кадр"] == б["кадр"]) != той_самий_кадр:
            continue
        пари.append(dict(а=а["запис"], б=б["запис"], розбіжні=розбіжні(а, б)))
    return dict(межа=межа, записів=len(рядки), кадрів=len({р["кадр"] for р in рядки}),
                пройшло=len(пройшли), поза_шумом=sum(р["шум"] is not None and р["шум"] > межа for р in рядки),
                пар=len(пари), розбіжних_тверджень=sum(len(п["розбіжні"]) for п in пари),
                розбіжні_пари=[п for п in пари if п["розбіжні"]])


def головна():
    """Звіряє файли, повторює незмінений вимір і зберігає числа та походження кожного запису."""
    сп = importlib.util.spec_from_file_location("вимір_набору", ТУТ.parent / "вимір-портрета-1211/вимір.py")
    В = importlib.util.module_from_spec(сп)
    сп.loader.exec_module(В)
    from PIL import Image
    import cv2
    import PIL

    фото, вихід = Path(sys.argv[1]) / "портрети", Path(sys.argv[2])
    маніфест_байти = (Path(sys.argv[3]) if len(sys.argv) > 3 else НАБІР / "набір.json").read_bytes()
    маніфест = json.loads(маніфест_байти)
    рядки = []
    стара_межа = В.ПВ.ШУМ_ЗОН_МЕЖА
    try:
        # Лише локальна діагностика: вимірюємо кожен кадр один раз, тоді застосовуємо всі межі до того самого шуму.
        # Інші ворота й внесок шуму в похибку/певність класів лишаються незмінними.
        В.ПВ.ШУМ_ЗОН_МЕЖА = float("inf")
        for ф in маніфест["кадри"]:
            if "sha256" not in ф:
                рядки.append(dict(кадр=ф["id"], людина=ф["людина"], спосіб="геометрія", запис=ф["id"],
                                 шум=None, стан_без_воріт_щік="пропуск", пропуск=ф.get("пропуск", "не одержано")))
                continue
            шлях = фото / (ф["id"] + ".jpg")
            if hashlib.sha256(шлях.read_bytes()).hexdigest() != ф["sha256"]:
                raise ValueError("Контрольна сума не збіглася: " + ф["id"])
            зображення = Image.open(шлях).convert("RGB")
            зони, причина = В.зони(зображення)
            записи = [("геометрія", ф["id"], зони, причина, None)]
            for п in sorted((НАБІР / "прогін").glob("*__" + ф["id"] + "*/VIDPOVIDI/*кольори_з_портрета.txt")):
                текст = п.read_text("utf-8")
                відповідь = json.loads(текст[текст.index("── ВІДПОВІДЬ"):].split("\n", 1)[1])
                записи.append(("модель", п.relative_to(НАБІР).as_posix(), В.ПВ.рамки(відповідь.get("zones")),
                               None, hashlib.sha256(п.read_bytes()).hexdigest()))
            for спосіб, запис, рамки, пропуск, сума in записи:
                р = dict(кадр=ф["id"], людина=ф["людина"], спосіб=спосіб, запис=запис,
                         sha256_фото=ф["sha256"], sha256_відповіді=сума, рамки=рамки,
                         розмір=list(зображення.size), шум=None, стан_без_воріт_щік="пропуск", пропуск=пропуск)
                if рамки:
                    кадри = {ім: В.вирізати(зображення, рамка) for ім, рамка in рамки.items()}
                    вимір = В.ПВ.виміряти(кадри)
                    р.update(стан_без_воріт_щік=вимір["стан"], причини=вимір["причини"],
                             шум=(вимір.get("шкіра") or {}).get("шум_зон"),
                             повтор_однаковий=вимір == В.ПВ.виміряти(кадри))
                    if вимір["стан"] == "вимір":
                        р["класи"] = В.заявлені(вимір)[0]
                        р["lab"] = {к: вимір[к]["lab"] for к in ("шкіра", "волосся", "очі")}
                рядки.append(р)
    finally:
        В.ПВ.ШУМ_ЗОН_МЕЖА = стара_межа
    if not рядки or not all(р.get("повтор_однаковий", True) for р in рядки):
        raise ValueError("Порожній або невідтворюваний вимір")
    підсумки = {спосіб: [підсумок([р for р in рядки if р["спосіб"] == спосіб], м) for м in МЕЖІ]
                for спосіб in ("геометрія", "модель")}
    повтори = підсумок([р for р in рядки if р["спосіб"] == "модель"], 4, той_самий_кадр=True)
    результат = dict(sha256_маніфесту=hashlib.sha256(маніфест_байти).hexdigest(),
                    версії=dict(python=sys.version.split()[0], opencv=cv2.__version__, pillow=PIL.__version__),
                    межа_продукту=стара_межа, підсумки=підсумки, повтори_моделі=повтори, записи=рядки)
    вихід.parent.mkdir(parents=True, exist_ok=True)
    вихід.write_text(json.dumps(результат, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    for спосіб, значення in підсумки.items():
        for р in значення:
            print(спосіб, "межа", р["межа"], "пройшло", р["пройшло"], "з", р["записів"],
                  "пар", р["пар"], "розбіжних", р["розбіжних_тверджень"])
    print("Повтори рамок моделі того самого кадру:", json.dumps(повтори, ensure_ascii=False))


if __name__ == "__main__":
    головна()
