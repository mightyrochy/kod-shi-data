"""Звірити придатність заміни на справжньому ендпойнті мови без виклику моделей."""
import json
import os
import pathlib
import sys

sys.path.insert(0, os.environ.get("E2_SOURCES", str(pathlib.Path(__file__).resolve().parents[3] / "джерела")))
import мовний_шар as М


def main():
    """Виміряти збереження й заміну прийнятих полів на всіх формах відповіді шару."""
    факти = []

    def звірити(назва, очікуване, значення):
        факт = значення == очікуване
        факти.append(факт)
        print(json.dumps(dict(випадок=назва, очікуване=очікуване, значення=значення, пройдено=факт), ensure_ascii=False))

    def повтор(контекст, перша, друга):
        return json.loads(М.мова(dict(контекст, перша_відповідь=json.dumps(перша),
                                      відповідь_моделі=json.dumps(друга), завершити_договір=True)))

    а = {"actions": [{"op": "remove", "item": "r1"}, {"op": "add", "kind": "bad", "color": "red"}]}
    б = {"actions": [{"op": "remove", "item": "r1"}, {"op": "add", "kind": "shirt", "color": "red"}]}
    р = повтор(dict(вхід="review_items_fix", слова="додай червону сорочку"), а, б)
    звірити("2082: виправлений add без id", М.прийняти_вхід("review_items_fix", json.dumps(б))["внутрішня"], р["внутрішня"])

    записи = pathlib.Path(__file__).resolve().parents[1] / "Е2-ремонт-шар/записи.json"
    сцена = json.loads(записи.read_text(encoding="utf8"))[0]
    сирий = next(в["відповідь"] for к, в in сцена["відповіді"].items() if "seed3_01_" in к)
    а, _ = М._обʼєкт(сирий)
    б = json.loads(json.dumps(а))
    б["update"]["occasion"] = {"value": "concert"}
    р = повтор(dict(розмова=dict(нове=сцена["слова"])), а, б)
    звірити("2082: цитата концерту", "рок-концерт у клубі", р["внутрішня"].get("event", {}).get("free_text"))
    б["update"]["occasion"]["value"] = "theatre"
    б["update"]["formality"] = "neat"
    б.pop("text", None)
    р = повтор(dict(розмова=dict(нове=сцена["слова"])), а, б)
    звірити("2082: прийняті факти без text", {"occasion": "theatre", "formality": {"from": 5, "to": 6}},
             {к: р["внутрішня"].get(к) for к in ("occasion", "formality")})

    розмітка = М.розмітити({"а": "A short message for you.", "б": "Another short message for you."})
    for назва, друга, очікуване in [
        ("частковий переклад", {"1": None, "2": "Ще одне повідомлення для тебе."}, "Коротке повідомлення для тебе."),
        ("придатна заміна перекладу", {"1": "Інше повідомлення для тебе."}, "Інше повідомлення для тебе."),
        ("невідомий переклад", {"1": "unknown"}, "Коротке повідомлення для тебе.")]:
        р = повтор(dict(розмітка=розмітка), {"1": "Коротке повідомлення для тебе."}, друга)
        звірити(назва, очікуване, р.get("тексти", {}).get("а"))
        if "2" in друга:
            звірити("дописаний переклад", друга["2"], р.get("тексти", {}).get("б"))

    for друга, очікуване in [({}, "Обрала тобі зручний образ."), ({"text": "Тепер обрала легкий образ."}, "Тепер обрала легкий образ.")]:
        р = повтор(dict(репліка={}), {"text": "Обрала тобі зручний образ."}, друга)
        звірити("репліка: збереження або заміна", очікуване, р.get("текст"))

    повідомлення = [{"ключ": "а", "повідомлення": "рядок", "вид": "x", "заяви": []},
                    {"ключ": "б", "повідомлення": "рядок", "вид": "x", "заяви": []}]
    р = повтор(dict(розмітка_повідомлень=повідомлення), {"а": "Перший рядок."}, {"а": None, "б": "Другий рядок."})
    звірити("заяви: частковий повтор", {"а": "Перший рядок.", "б": "Другий рядок."}, р.get("тексти"))
    звірити("заяви: обидва тексти прийняті", ["translated", "translated"], [з["стан"] for з in р.get("заяви", [])])
    звірити("заяви: пропусків немає", [], р.get("без_відповіді"))

    запити = [dict(розмітка=розмітка, відповідь_моделі=json.dumps({"1": "Коротке повідомлення для тебе."})),
              dict(розмітка=розмітка, відповідь_моделі=json.dumps({"1": "Інше повідомлення для тебе.", "2": "Другий рядок для тебе."}),
                   відхилені_тексти=["а"])]
    р = json.loads(М.мова(dict(відповіді_шару=запити)))
    звірити("сторож показу до злиття", "Коротке повідомлення для тебе.", р.get("тексти", {}).get("а"))
    звірити("сторож не знімає решту повтору", "Другий рядок для тебе.", р.get("тексти", {}).get("б"))

    for цитата in (42, None, "unknown", " "):
        р = повтор(dict(вхід="scenario"), {"place": {"quote": "у клубі", "value": "club"}},
                   {"place": {"quote": цитата, "value": "cafe"}})
        звірити("непридатна цитата з придатним кодом", {"place": "cafe", "quotes": {"place": "у клубі"}}, р["внутрішня"])

    print(json.dumps(dict(усього=len(факти), пройдено=sum(факти), втрат=len(факти) - sum(факти)), ensure_ascii=False))
    return 0 if all(факти) else 1


if __name__ == "__main__":
    sys.exit(main())
