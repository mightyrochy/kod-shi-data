# -*- coding: utf-8 -*-
"""Е3-одна-величина ч30 (п.7, слово довжини моделі → точка речі на тілі): ДО → ПІСЛЯ.

Запуск із кореня репозиторію:
    python3 аудит/проби/Е3_ч30_слово_моделі_точка.py                       # ПІСЛЯ: код цієї гілки
    git worktree add /tmp/до <SHA_ДО>
    python3 аудит/проби/Е3_ч30_слово_моделі_точка.py --код /tmp/до/джерела  # ДО: той самий скрипт на старому коді

Тіла — 155/165/175 см, обхвати стенда 98/92/74/100 (`fit.тіло`), як у `Е3_ч26_клас_довжини.py`. Друкує:
  · кожен код довжини моделі (`ТАБЛИЦЯ["length"]`): слово схеми, клас у `довжина_рівень` речі з фото
    (`річ_з_фото.запис_каталогу`) і край цієї речі на тілах (`композитор_річ.висота_рівня`: центр ± півширина);
  · таблиці слів: `ДОВЖИНА_СЛОВОМ` (клас → слово мови) і `жнива_реєстр.ДОВЖИНА_В_РІВЕНЬ` — той самий вміст;
  · дефолтний край великої речі слота для площі схеми (`палітра_схеми`): верх і низ см на тілах."""
import sys, pathlib, os, io, contextlib

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
код = pathlib.Path(sys.argv[sys.argv.index("--код") + 1]).resolve() if "--код" in sys.argv else КОРІНЬ / "джерела"
os.chdir(код); sys.path.insert(0, str(код))
with contextlib.redirect_stdout(io.StringIO()):
    import fit as ПС, композитор_річ as КР, річ_з_фото as РФ, внутрішня_мова as ВМ, жнива_реєстр as ЖР
    import палітра_схеми as ПАЛ
print(f"код: {код}")
ТІЛА = {зр: ПС.тіло(зр, dict(плечі=98, груди=92, талія=74, стегна=100)) for зр in (155, 165, 175)}

слова = getattr(РФ, "ДОВЖИНИ_МОДЕЛІ", None)
схема_слово = {к: с for с, к, _ in слова} if слова else {к: с for к, с in РФ._довжини_кодів().items()}
print("код довжини моделі → слово схеми → клас у `довжина_рівень` → край см на 155 / 165 / 175 (центр ± півширина)")
for к, сл in ВМ.ТАБЛИЦЯ["length"].items():
    слово = РФ._довжини_кодів().get(к)
    з = РФ.запис_каталогу(dict(ід="п", слот="низ", довжина=слово))
    клас = з.get("довжина_рівень")
    вис = " / ".join("%s ± %s" % КР.висота_рівня(клас, t["висоти"]) for t in ТІЛА.values())
    print("   %-10s %-8s %-8s %s" % (к, слово, клас, вис))
print("ДОВЖИНА_СЛОВОМ:", dict(sorted(РФ.ДОВЖИНА_СЛОВОМ.items())))
print("жнива_реєстр.ДОВЖИНА_В_РІВЕНЬ:", ЖР.ДОВЖИНА_В_РІВЕНЬ)
print("дефолтний край великої речі слота для площі схеми (верх см, низ см) на 155 / 165 / 175")
for слот in ("верх", "низ", "сукня", "комплект", "верхній_шар"):
    деф = []
    for t in ТІЛА.values():
        H = t["висоти"]
        if hasattr(ПАЛ, "_краї_слота"):
            деф.append(tuple(round(x, 1) for x in ПАЛ._краї_слота(слот, H)))
        else:
            деф.append(tuple(round(H[x], 1) for x in ПАЛ._КРАЇ_СЛОТА[слот]))
    print("   %-12s %s" % (слот, " / ".join(map(str, деф))))
