# РВ-2 З-3 (рядок 9 дошки): оголошений хід ітерації 2 («свідомо» → ×0.6) гине на
# виклику 3 (ВИБІР_V1), тому опис і журнал несуть ПОВНУ силу знахідки, а друга
# ітерація просить полагодити те, що ші зробила навмисно.
# Повторює рівно ті виклики, що робить показ. Склад образу — 4 речі із сукнею
# (мінімум структури, #55): на двох речах вибір гине ще до оголошення.
# Запуск: python3 аудит/проби/рв2_свідомі_на_виборі.py
import sys, os, json, tempfile
ДЖ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "джерела")
sys.path.insert(0, ДЖ); os.chdir(ДЖ)
import bridge as B, feed as Ф

вх = json.load(open("стенд_вх.json", encoding="utf-8"))
d0 = dict(вх, каталог=Ф.каталог_на_диску("каталог_brief.xml"), варіантів=10, ремонт_варіантів=5,
          кеш_кольорів=os.path.join(tempfile.gettempdir(), "кеш_проби_рв2.json"))
міст = lambda **kw: json.loads(B.виклик("від_моделі", json.dumps(dict(d0, **kw), ensure_ascii=False)))
пул = json.loads(json.loads(B.виклик("запити", json.dumps(d0, ensure_ascii=False)))["руки"]["1"])["пул"]
н = lambda сл, i=0: пул[сл][i]["н"]
сила = lambda зн: [(z.get("сила_нп"), bool(z.get("свідомий"))) for z in (зн or []) if z.get("правило") == "K-KOH-06"]

склад = [н("сукня", 3), н("взуття"), н("сумка"), н("каблучка")]
відп2 = dict(версія="1", образи=[
    dict(ід="о1", підпис="вечірній тон", речі=склад,
         свідомо=[dict(річ=н("взуття"), чому="ці мюлі взяті навмисно, це задум образу")]),
    dict(ід="о2", підпис="без оголошення", речі=[н("сукня", 4), н("взуття"), н("сумка"), н("каблучка")])])
в2 = міст(ітерація=2, текст_моделі=json.dumps(відп2, ensure_ascii=False))
о1 = в2["вердикт"]["образи"][0]
print("ітерація 2, о1: K-KOH-06 (сила, свідомий) %s · вердикт несе оголошення: %s"
      % (сила(о1["знахідки"]), [с.get("річ") for с in (о1.get("свідомі") or [])]))
в3 = міст(ітерація=2, відповідь="ВИБІР_V1", вибір_над=в2["вибір_над"],
          текст_моделі=json.dumps(dict(версія="1", обрано="о1", чому="тримає задум"), ensure_ascii=False))
вб = в3["вибір"]
print("виклик 3 (ВИБІР_V1 «о1»): обрано %s · відмова %s · розриви %s · K-KOH-06 %s"
      % (вб["обрано"], вб["чому_відмова"], [р.get("річ") for р in (вб.get("розриви") or [])],
         сила(в3.get("знахідки"))))
оп = json.loads(B.виклик("опис", json.dumps(dict(d0, речі=вб["ід"], підпис=вб["підпис"], номери=вб["номери"],
                                                 образ=вб["обрано"],
                                                 свідомі=[x.get("текст") for x in (в3.get("свідомі") or [])]),
                                            ensure_ascii=False)))
print("виклик 4, ОПИС_V1.свідомі: %s" % оп["опис"].get("свідомі"))
