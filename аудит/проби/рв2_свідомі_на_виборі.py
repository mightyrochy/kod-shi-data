# (ВИБІР_V1), тому ОПИС_V1.свідомі порожнє, а фінальний суд і журнал несуть повну силу.
# Повторює рівно ті виклики, що робить показ. Запуск: python3 аудит/проби/рв2_свідомі_на_виборі.py
import sys, os, json, tempfile
ДЖ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "джерела")
sys.path.insert(0, ДЖ); os.chdir(ДЖ)
import bridge as B, feed as Ф

вх = json.load(open("стенд_вх.json", encoding="utf-8"))
d0 = dict(вх, каталог=Ф.каталог_на_диску("каталог_brief.xml"), варіантів=10, ремонт_варіантів=5,
          кеш_кольорів=os.path.join(tempfile.gettempdir(), "кеш_проби_рв2.json"))
міст = lambda **kw: json.loads(B.виклик("від_моделі", json.dumps(dict(d0, **kw), ensure_ascii=False)))
пул = json.loads(json.loads(B.виклик("запити", json.dumps(d0, ensure_ascii=False)))["руки"]["1"])["пул"]
сукні, вз = [r["н"] for r in пул["сукня"]], пул["взуття"][0]["н"]
сила = lambda зн: [(z.get("сила_нп"), bool(z.get("свідомий"))) for z in (зн or []) if z.get("правило") == "K-KOH-06"]

відп2 = dict(версія="1", образи=[
    dict(ід="о1", підпис="вечірній тон", речі=[сукні[3], вз],
         свідомо=[dict(річ=сукні[3], чому="світлий тон узятий навмисно, це задум образу")]),
    dict(ід="о2", підпис="інша сукня", речі=[сукні[4], вз])])
в2 = міст(ітерація=2, текст_моделі=json.dumps(відп2, ensure_ascii=False))
print("ітерація 2, о1 у вердикті: K-KOH-06 %s · свідомі запису о1: %s"
      % (сила(в2["вердикт"]["образи"][0]["знахідки"]), в2["образи"][0].get("свідомі")))
в3 = міст(ітерація=2, відповідь="ВИБІР_V1", вибір_над=в2["вибір_над"],
          текст_моделі=json.dumps(dict(версія="1", обрано="о1", чому="тримає задум"), ensure_ascii=False))
print("виклик 3 (ВИБІР_V1 «о1»): речей %d · в.свідомі %s · K-KOH-06 %s · у вердикті %s"
      % (len(в3.get("речі") or []), в3.get("свідомі"), сила(в3.get("знахідки")),
         сила(в3["вердикт"]["образи"][0]["знахідки"])))
вб = в3["вибір"]
свід_показу = [x.get("текст") or x for x in (в3.get("свідомі") or [])]     # рівно те, що шле показ в `опис`
оп = json.loads(B.виклик("опис", json.dumps(dict(d0, речі=вб["ід"], підпис=вб["підпис"], номери=вб["номери"],
                                                 образ=вб["обрано"], свідомі=свід_показу), ensure_ascii=False)))
print("виклик 4, ОПИС_V1.свідомі: %s" % оп["опис"].get("свідомі"))
в4 = міст(ід=вб["ід"], ітерація=2, відповідь="ОПИС_ВІДПОВІДЬ_V1",
          текст_моделі=json.dumps(dict(версія="1", текст="Сукня світла, човники чорні."), ensure_ascii=False))
print("виклик 4, суд: K-KOH-06 %s · в.свідомі %s → у журнал іде сила %s"
      % (сила(в4.get("знахідки")), в4.get("свідомі"),
         [з["сила_нп"] for з in в4["знахідки"] if з["правило"] == "K-KOH-06"]))
