"""Випадкова вибірка 40 речей дельти перезбору, що змінили колір, для приймання 38/40 очима (п.18).

Вхід — гілка даних `claude/Річ-колір-вимір` на голові ГОЛОВА (читається `git show`, без checkout):
`дельта.json.gz` (нові записи й маніфест фото), `кадри_ДО.json.gz` (старі записи), фото кадрів.
Назву й колір крамниці дає `каталог_повний.xml.gz` з кореня репозиторію.

Сукупність — речі, де хоч один кадр після перезбору має придатний вимір (`колір_тип` «вимір»,
`придатна`) з hex, відмінним від старого, і фото в маніфесті. Річ — рівноймовірно з сукупності
(`random.Random(ЗЕРНО).sample` по відсортованих id), кадр речі — рівноймовірно з її змінених кадрів
тим самим генератором. Вихід — `вибірка.tsv` і фото 40 кадрів у теку з аргументу (для огляду).

Запуск із кореня репозиторію: python3 -I аудит/проби/річ_колір_приймання_0811/вибірка.py <тека_фото>
"""
import csv
import gzip
import html
import json
import random
import re
import subprocess
import sys
from pathlib import Path

ГОЛОВА = "43dd34adee5bf462c70cbdc9f01719da7250719e"
ТЕКА_ДАНИХ = "аудит/проби/річ_колір_перезбір_0411/"
ЗЕРНО = 20261108
РЕЧЕЙ = 40
ТУТ = Path(__file__).resolve().parent
КОРІНЬ = ТУТ.parents[2]


def показати(шлях):
    """Байти файла гілки даних на голові ГОЛОВА."""
    return subprocess.run(["git", "show", "%s:%s%s" % (ГОЛОВА, ТЕКА_ДАНИХ, шлях)], cwd=КОРІНЬ,
                          check=True, capture_output=True).stdout


def підписи(ід_без_крамниці):
    """Назва й колір крамниці з повного каталогу (param «Колір», якщо є)."""
    текст = gzip.open(КОРІНЬ / "каталог_повний.xml.gz", "rt", encoding="utf-8").read()
    вих = {}
    for ід, тіло in re.findall(r'<offer id="([^"]+)"(.*?)</offer>', текст, re.S):
        if ід not in ід_без_крамниці:
            continue
        назва = re.search(r"<name>(.*?)</name>", тіло, re.S)
        колір = [html.unescape(з) for н, з in re.findall(r'<param name="([^"]*)">(.*?)</param>', тіло, re.S)
                 if re.fullmatch(r"~?\s*(колір|цвет|color|колір товару)\s*", н, re.I)]
        вих[ід] = (html.unescape(назва.group(1)) if назва else "", колір[0] if колір else "")
    return вих


def головна():
    тека_фото = Path(sys.argv[1])
    тека_фото.mkdir(parents=True, exist_ok=True)
    дельта = json.loads(gzip.decompress(показати("дельта.json.gz")))
    до = json.loads(gzip.decompress(показати("кадри_ДО.json.gz")))["записи"]
    маніфест = {(м["id"], м["файл"], м["url"]): м for м in дельта["маніфест"]}
    сукупність = {}
    for ід, записи in дельта["записи"].items():
        старі = {в["файл"]: в for в in до[ід]}
        змінені = [(в, старі.get(в["файл"], {}), маніфест[ід, в["файл"], в["url"]]) for в in записи
                   if в.get("колір_тип") == "вимір" and в.get("придатна") is True and в.get("hex")
                   and в["hex"] != старі.get(в["файл"], {}).get("hex") and (ід, в["файл"], в["url"]) in маніфест]
        if змінені:
            сукупність[ід] = змінені
    генератор = random.Random(ЗЕРНО)
    обрані = генератор.sample(sorted(сукупність), РЕЧЕЙ)
    назви = підписи({ід.split("@")[0] for ід in обрані})
    рядки = []
    for номер, ід in enumerate(обрані, 1):
        в, с, м = генератор.choice(сукупність[ід])
        фото = тека_фото / ("%02d.jpg" % номер)
        фото.write_bytes(показати(м["фото"]))
        назва, колір_крамниці = назви.get(ід.split("@")[0], ("", ""))
        рядки.append(dict(
            номер=номер, річ=ід, назва=назва, колір_крамниці=колір_крамниці,
            кадр=м["фото"], клас=в.get("клас") or "", кадрів_змінено=len(сукупність[ід]),
            hex_до=с.get("hex") or "", hex_після=в["hex"], код_до=с.get("слово") or "", код_після=в["слово"],
            кластери=" ".join("%s:%s:%.2f" % (к[0], к[2], к[1]) for к in в.get("кластери", [])),
            візерунок=(в.get("вимір") or {}).get("візерунок") or "", маска=в.get("маска") or "",
            частка_маски=в.get("частка_маски"), розкид=в.get("розкид"), чому=в.get("чому") or ""))
    with (ТУТ / "вибірка.tsv").open("w", encoding="utf-8", newline="") as файл:
        писар = csv.DictWriter(файл, fieldnames=list(рядки[0]), delimiter="\t")
        писар.writeheader()
        писар.writerows(рядки)
    print("сукупність: речей %d, кадрів %d; зерно %d; обрано %d" %
          (len(сукупність), sum(map(len, сукупність.values())), ЗЕРНО, len(рядки)))


if __name__ == "__main__":
    головна()
