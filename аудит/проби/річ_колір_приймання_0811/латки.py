def лаб_hex(hex_):
    return CS.to_lab(tuple(int(hex_[і:і + 2], 16) for і in (1, 3, 5)))


def головна():
    тека = Path(sys.argv[1])
    рядки = list(csv.DictReader((ТУТ / "вибірка.tsv").open(encoding="utf-8"), delimiter="\t"))
    вих = []
    for р in рядки:
        н = int(р["номер"])
        im = Image.open(тека / ("%02d.jpg" % н)).convert("RGB")
        w, h = im.size
        x0, y0, x1, y1 = ЛАТКИ[н]
        шмат = im.crop((round(x0 * w), round(y0 * h), round(x1 * w), round(y1 * h))).resize((60, 60))
        лаби = [CS.to_lab(п) for п in (шмат.get_flattened_data() if hasattr(шмат, "get_flattened_data") else шмат.getdata())]
        лаб = tuple(statistics.median(л[к] for л in лаби) for к in range(3))
        вимір = лаб_hex(р["hex_після"])
        L, C, гт = CS.lch(лаб)
        Lв, Cв, гв = CS.lch(вимір)
        код, у_вікні = П.слово_з_lab(лаб)
        вих.append(dict(номер=н, hex_латки=CS.hex_з_lab(лаб), LCh_латки="%.0f/%.0f/%.0f" % (L, C, гт),
                        hex_після=р["hex_після"], LCh_виміру="%.0f/%.0f/%.0f" % (Lв, Cв, гв),
                        ΔE00=round(CS.de00(лаб, вимір), 1), код_латки=код, код_після=р["код_після"]))
    with (ТУТ / "латки.tsv").open("w", encoding="utf-8", newline="") as ф:
        п = csv.DictWriter(ф, fieldnames=list(вих[0]), delimiter="\t")
        п.writeheader()
        п.writerows(вих)
    for р in вих:
        print("\t".join(str(в) for в in р.values()))


if __name__ == "__main__":
    головна()
