"""ДО→ПІСЛЯ ж5 хід 2: записана відповідь моделі → прийняти_розмову → паспорт_з_шару (без моделі)."""
import sys, json
sys.path.insert(0, sys.argv[1])
import мовний_шар as М
т = open(sys.argv[2], encoding='utf8').read()
відп = т.split('── ВІДПОВІДЬ', 1)[1].split('──\n', 1)[1]
р = М.прийняти_розмову(відп)
р = М._ДМШ.зберегти_подію(р, None) if hasattr(М, '_ДМШ') else р
слова = ["завтра співбесіда в банку на посаду аналітика, о десятій ранку", "тільки не чорне, і без підборів"]
п = М.паспорт_з_шару(р["внутрішня"], {}, слова_ходу=слова, частини=р.get("частини"),
                     не_взято=р.get("не_взято"), не_записано_ходу=р.get("не_записано"))
ПП = п["паспорт"]
print("вето_тверде:", json.dumps({к: в for к, в in (ПП.get("вето_тверде") or {}).items() if в}, ensure_ascii=False))
print("решта (її слова стилістці):", ПП.get("решта"))
print("not_recorded:", п.get("не_записано"), "| partly_recorded:", п.get("частково_записано"))
print("«без підборів» у паспорті:", "без підборів" in json.dumps(ПП, ensure_ascii=False))
