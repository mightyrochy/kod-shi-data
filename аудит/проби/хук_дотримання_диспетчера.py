#!/usr/bin/env python3
"""Проба П15: `.claude/хуки/дотримання_диспетчера.py` — чотири точки дії диспетчера (корінь ПК-дотримання-правил, крок 09.11).

Запуск: python3 -I аудит/проби/хук_дотримання_диспетчера.py [шлях_до_хука]   (без аргументу — хук з робочого дерева).
Транскрипти й виклики штучні. Мірило: кожна точка повертає раз; не повертаються — повтор, лист менеджерові чи
диспетчерові, слово, звернене до диспетчера, хід сесії до 24 год, перше нагадування, пульс, лист без розкладу, не
диспетчер, субагент. ДО (хука нема) повертали 0 з 6 порушень (передача, 2 слова, лист, 2 нагадування); ПІСЛЯ — 6 з 6, хибних повернень 0.
"""
import json
import os
import subprocess
import sys
import tempfile

КОРІНЬ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
ХУК = sys.argv[1] if len(sys.argv) > 1 else os.path.join(КОРІНЬ, ".claude", "хуки", "дотримання_диспетчера.py")
МЕНЕДЖЕР, ДИСПЕТЧЕР, ВИКОНАВЕЦЬ = "session_MGR1", "session_DSP1", "session_EXE1"
СТАН = f"| роль | сесія |\n|---|---|\n| диспетчер | {ДИСПЕТЧЕР} (ДИСПЕТЧЕР-1) |\n| менеджер | {МЕНЕДЖЕР} |\n"
ЗАРАЗ = "2026-11-10T12:00:00Z"
ЛИСТ = "mcp__claude-code-remote__send_message"
ПІЗНІШЕ = "mcp__claude-code-remote__send_later"
ТРИГЕР = "mcp__claude-code-remote__create_trigger"
ПРОДУКТ = "Стилістка має пропонувати теплі тканини взимку, а не лише легкі сукні."


def слово(текст, коли="2026-11-10T11:00:00Z"):
    return {"type": "user", "timestamp": коли, "origin": {"kind": "human"}, "message": {"role": "user", "content": текст}}


def лист(кому, текст, коли="2026-11-10T11:05:00Z"):
    return {"type": "assistant", "timestamp": коли, "message": {"role": "assistant", "content": [
        {"type": "tool_use", "id": "t" + str(abs(hash(текст)) % 999), "name": ЛИСТ,
         "input": {"session_id": кому, "message": текст}}]}}


def кінець(коли="2026-11-10T11:10:00Z"):
    return {"type": "assistant", "timestamp": коли, "message": {"role": "assistant", "stop_reason": "end_turn",
                                                                  "content": [{"type": "text", "text": "—"}]}}


def початок(коли):
    return {"type": "user", "timestamp": коли, "origin": {"kind": "task-notification"},
            "message": {"role": "user", "content": "<task-notification>x</task-notification>"}}


def запуск(тека, вхід, записи=None, я=ДИСПЕТЧЕР, додатково=None):
    шлях = os.path.join(тека, "т.jsonl")
    with open(шлях, "w", encoding="utf-8") as ф:
        for з in записи or []:
            ф.write(json.dumps(з, ensure_ascii=False) + "\n")
    os.makedirs(os.path.join(тека, "аудит"), exist_ok=True)
    with open(os.path.join(тека, "аудит", "СТАН.md"), "w", encoding="utf-8") as ф:
        ф.write(СТАН)
    вхід = dict({"transcript_path": шлях}, **вхід, **(додатково or {}))
    env = dict(os.environ, CLAUDE_PROJECT_DIR=тека, ДОТРИМАННЯ_ТЕКА=os.path.join(тека, "стан"), ДОТРИМАННЯ_ЗАРАЗ=ЗАРАЗ,
               CLAUDE_CODE_REMOTE_SDK_URL=f"https://x/sessions/cse_{я[len('session_'):]}")
    р = subprocess.run([sys.executable, ХУК], input=json.dumps(вхід, ensure_ascii=False), capture_output=True,
                       text=True, encoding="utf-8", env=env)
    ви = json.loads(р.stdout) if р.stdout.strip() else {}
    причина = ви.get("reason") or (ви.get("hookSpecificOutput") or {}).get("permissionDecisionReason") or ""
    факт = "пропуск"
    for назва, ознака in (("передача", "ДИСПЕТЧЕР ПЕРЕДАЧА"), ("слово", "не переслано менеджерові"),
                          ("лист", "create_trigger(persistent_session_id"), ("нагадування", "Попереднє нагадування")):
        if ознака in причина:
            факт = назва if факт == "пропуск" else факт + "+" + назва
    return (факт if причина else "пропуск") + (" +stderr" if р.stderr.strip() else "")


def стоп(записи, **к):
    return ({}, записи, к)


def випадки():
    давно, нещодавно = "2026-11-09T10:00:00Z", "2026-11-10T02:00:00Z"
    слово_лист = f"СЛОВО ВЛАСНИКА 11:00 UTC: «{ПРОДУКТ}»"
    пізніше = {"tool_name": ПІЗНІШЕ, "tool_input": {"delay_minutes": 40, "message": "CI #5"}}
    пізніше_2 = {"tool_name": ПІЗНІШЕ, "tool_input": {"delay_minutes": 20, "message": "CI #6"}}
    return [
        # (назва, [(вхід, записи, ключі)…], чекано останнього)
        ("передача: понад 24 год, листа нема", [({}, [початок(давно), кінець()], {})], "передача"),
        ("передача: лист є", [({}, [початок(давно), лист(МЕНЕДЖЕР, "ДИСПЕТЧЕР ПЕРЕДАЧА #9 claude/передача"), кінець()], {})], "пропуск"),
        ("передача: хід до 24 год", [({}, [початок(нещодавно), кінець()], {})], "пропуск"),
        ("передача: повтор після повернення", [({}, [початок(давно), кінець()], {}), ({}, [початок(давно), кінець()], {})], "пропуск"),
        ("слово власника не переслано", [({}, [слово(ПРОДУКТ), кінець()], {})], "слово"),
        ("слово переслано дослівно", [({}, [слово(ПРОДУКТ), лист(МЕНЕДЖЕР, слово_лист), кінець()], {})], "пропуск"),
        ("слово: наказ диспетчерові без «ти» й «?»", [({}, [слово("Запусти прогін на ноутбуці зараз, не чекай слотів."), кінець()], {})], "пропуск"),
        ("слово: звертання за ім'ям ролі", [({}, [слово("Диспетчере, розбери чергу нарядів і скажи, що простоює."), кінець()], {})], "пропуск"),
        ("слово про продукт з «?»", [({}, [слово("Чому стилістка радить білу сукню взимку? Це ж каталог крамниць."), кінець()], {})], "слово"),
        ("слово: коротка відповідь", [({}, [слово("так, роби"), кінець()], {})], "пропуск"),
        ("слово: хід почав не власник", [({}, [початок(нещодавно), кінець()], {})], "пропуск"),
        ("слово: повтор після повернення", [({}, [слово(ПРОДУКТ), кінець()], {}), ({}, [слово(ПРОДУКТ), кінець()], {})], "пропуск"),
        ("Stop: stop_hook_active", [({}, [слово(ПРОДУКТ), кінець()], {"stop_hook_active": True})], "пропуск"),
        ("Stop: субагент", [({}, [слово(ПРОДУКТ), кінець()], {"agent_id": "a1"})], "пропуск"),
        ("лист виконавцю", [({"tool_name": ЛИСТ, "tool_input": {"session_id": ВИКОНАВЕЦЬ, "message": "Почни"}}, [], {})], "лист"),
        ("лист менеджерові", [({"tool_name": ЛИСТ, "tool_input": {"session_id": МЕНЕДЖЕР, "message": "КОЛО"}}, [], {})], "пропуск"),
        ("лист диспетчерові", [({"tool_name": ЛИСТ, "tool_input": {"session_id": ДИСПЕТЧЕР, "message": "ГОТОВО"}}, [], {})], "пропуск"),
        ("повтор листа виконавцю", [({"tool_name": ЛИСТ, "tool_input": {"session_id": ВИКОНАВЕЦЬ, "message": "Почни"}}, [], {})] * 2, "пропуск"),
        ("лист не від диспетчера", [({"tool_name": ЛИСТ, "tool_input": {"session_id": ВИКОНАВЕЦЬ, "message": "x"}}, [], {"__я": "session_EXE1"})], "пропуск"),
        ("нагадування: перше", [(пізніше, [], {})], "пропуск"),
        ("нагадування: друге до першого", [(пізніше, [], {}), (пізніше_2, [], {})], "нагадування"),
        ("нагадування: повтор того самого", [(пізніше, [], {}), (пізніше_2, [], {}), (пізніше_2, [], {})], "пропуск"),
        ("нагадування: після настання першого", [({"tool_name": ПІЗНІШЕ, "tool_input": {"at": "2026-11-10T11:00:00Z", "message": "a"}}, [], {}),
                                                  (пізніше_2, [], {})], "пропуск"),
        ("нагадування: create_trigger run_once_at до першого", [(пізніше, [], {}),
                                                                ({"tool_name": ТРИГЕР, "tool_input": {"run_once_at": "2026-11-10T14:00:00Z", "prompt": "CI"}}, [], {})], "нагадування"),
        ("пульс із розкладом", [(пізніше, [], {}), ({"tool_name": ТРИГЕР, "tool_input": {"cron_expression": "0 * * * *", "prompt": "ПУЛЬС: такт", "persistent_session_id": ДИСПЕТЧЕР}}, [], {})], "пропуск"),
        ("create_trigger без розкладу", [(пізніше, [], {}), ({"tool_name": ТРИГЕР, "tool_input": {"persistent_session_id": ВИКОНАВЕЦЬ, "prompt": "Почни"}}, [], {})], "пропуск"),
        ("нагадування: субагент", [(пізніше, [], {}), (dict(пізніше_2, agent_id="a1"), [], {})], "пропуск"),
    ]


def main():
    збої = 0
    for назва, кроки, чекано in випадки():
        with tempfile.TemporaryDirectory() as т:
            факт = ""
            for вхід, записи, к in кроки:
                я = к.pop("__я", ДИСПЕТЧЕР) if "__я" in к else ДИСПЕТЧЕР
                факт = запуск(т, вхід, записи, я, к)
        збої += факт != чекано
        print(f"{'ок ' if факт == чекано else 'ЗБІЙ'} {назва} → {факт} (чекано {чекано})")
    with tempfile.TemporaryDirectory() as т:  # транскрипту нема — пропуск з попередженням
        факт = запуск(т, {"transcript_path": os.path.join(т, "нема.jsonl")}, None)
        очікувано = "пропуск"
        збої += not факт.startswith(очікувано)
        print(f"{'ок ' if факт.startswith(очікувано) else 'ЗБІЙ'} транскрипту нема → {факт} (чекано {очікувано}…)")
    print("збоїв:", збої)
    sys.exit(1 if збої else 0)


main()
