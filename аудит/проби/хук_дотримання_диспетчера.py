#!/usr/bin/env python3
"""Проба П15: `.claude/хуки/дотримання_диспетчера.py` — чотири точки дії диспетчера (корінь ПК-дотримання-правил, крок 09.11).

Запуск: python3 -I аудит/проби/хук_дотримання_диспетчера.py [шлях_до_хука] [--до] (без шляху — хук з робочого дерева).
Транскрипти й виклики штучні. --до перевіряє старе правило на базовому хуку, без прапорця — два виходи за п.19.
Мірило: кожна точка повертає раз; не повертаються — повтор, лист менеджерові чи
диспетчерові, хід сесії до 24 год, перше нагадування, пульс, лист без розкладу, не диспетчер, субагент.
Зміст слова визначає сесія після нагадування; те саме слово не повертається вдруге навіть у новому наборі слів.
"""
import json
