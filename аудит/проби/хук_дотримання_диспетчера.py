import subprocess
import sys
import tempfile

КОРІНЬ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
ДО = "--до" in sys.argv[1:]
ХУК = next((а for а in sys.argv[1:] if а != "--до"),
           os.path.join(КОРІНЬ, ".claude", "хуки", "дотримання_диспетчера.py"))
МЕНЕДЖЕР, ДИСПЕТЧЕР, ВИКОНАВЕЦЬ = "session_MGR1", "session_DSP1", "session_EXE1"
СТАН = f"| роль | сесія |\n|---|---|\n| диспетчер | {ДИСПЕТЧЕР} (ДИСПЕТЧЕР-1) |\n| менеджер | {МЕНЕДЖЕР} |\n"
ЗАРАЗ = "2026-11-10T12:00:00Z"
ЛИСТ = "mcp__claude-code-remote__send_message"
ПІЗНІШЕ = "mcp__claude-code-remote__send_later"
ТРИГЕР = "mcp__claude-code-remote__create_trigger"
ПРОДУКТ = "Стилістка має пропонувати теплі тканини взимку, а не лише легкі сукні."
КОДЕКС = "Давай більше роботи кодексу. Його ліміт зараз палиться повільніше за Клод"


def слово(текст, коли="2026-11-10T11:00:00Z"):
    return {"type": "user", "timestamp": коли, "origin": {"kind": "human"}, "message": {"role": "user", "content": текст}}


def лист(кому, текст, коли="2026-11-10T11:05:00Z"):
    return {"type": "assistant", "timestamp": коли, "message": {"role": "assistant", "content": [
        {"type": "tool_use", "id": "t" + str(abs(hash(текст)) % 999), "name": ЛИСТ,
         "input": {"session_id": кому, "message": текст}}]}}


def текст_асистента(текст):
    return {"type": "assistant", "message": {"role": "assistant", "content": [{"type": "text", "text": текст}]}}


def кінець(коли="2026-11-10T11:10:00Z"):
    return {"type": "assistant", "timestamp": коли, "message": {"role": "assistant", "stop_reason": "end_turn",
                                                                  "content": [{"type": "text", "text": "—"}]}}


def початок(коли):
    return {"type": "user", "timestamp": коли, "origin": {"kind": "task-notification"},
            "message": {"role": "user", "content": "<task-notification>x</task-notification>"}}


def запуск(тека, вхід, записи=None, я=ДИСПЕТЧЕР, додатково=None, з_причиною=False):
    шлях = os.path.join(тека, "т.jsonl")
    with open(шлях, "w", encoding="utf-8") as ф:
        for з in записи or []:
            ф.write(json.dumps(з, ensure_ascii=False) + "\n")
    os.makedirs(os.path.join(тека, "аудит"), exist_ok=True)
    with open(os.path.join(тека, "аудит", "СТАН.md"), "w", encoding="utf-8") as ф:
        ф.write(СТАН)
    вхід = dict({"transcript_path": шлях}, **вхід, **(додатково or {}))
    env = dict(os.environ, CLAUDE_PROJECT_DIR=тека, ДОТРИМАННЯ_ТЕКА=os.path.join(тека, "стан"), ДОТРИМАННЯ_ЗАРАЗ=ЗАРАЗ,
               CLAUDE_CODE_REMOTE_SDK_URL=f"https://x/sessions/cse_{я[len('session_'):]}")
    р = subprocess.run([sys.executable, ХУК], input=json.dumps(вхід, ensure_ascii=False), capture_output=True,
                       text=True, encoding="utf-8", env=env)
    ви = json.loads(р.stdout) if р.stdout.strip() else {}
    причина = ви.get("reason") or (ви.get("hookSpecificOutput") or {}).get("permissionDecisionReason") or ""
    факт = "пропуск"
    for назва, ознака in (("передача", "ДИСПЕТЧЕР ПЕРЕДАЧА"), ("слово", "не переслано менеджерові"),
                          ("лист", "create_trigger(persistent_session_id"), ("нагадування", "Попереднє нагадування")):
        if ознака in причина:
            факт = назва if факт == "пропуск" else факт + "+" + назва
    результат = (факт if причина else "пропуск") + (" +stderr" if р.stderr.strip() else "")
    return (результат, причина) if з_причиною else результат


def стоп(записи, **к):
    return ({}, записи, к)


