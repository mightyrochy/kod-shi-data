def main():
    збої = 0
    for назва, кроки, чекано in випадки():
        with tempfile.TemporaryDirectory() as т:
            факт = ""
            for вхід, записи, к in кроки:
                я = к.pop("__я", ДИСПЕТЧЕР) if "__я" in к else ДИСПЕТЧЕР
                факт = запуск(т, вхід, записи, я, к)
        збої += факт != чекано
        print(f"{'ок ' if факт == чекано else 'ЗБІЙ'} {назва} → {факт} (чекано {чекано})")
    with tempfile.TemporaryDirectory() as т:  # транскрипту нема — пропуск з попередженням
        факт = запуск(т, {"transcript_path": os.path.join(т, "нема.jsonl")}, None)
        очікувано = "пропуск"
        збої += not факт.startswith(очікувано)
        print(f"{'ок ' if факт.startswith(очікувано) else 'ЗБІЙ'} транскрипту нема → {факт} (чекано {очікувано}…)")
    with open(os.path.join(КОРІНЬ, "AGENTS.md"), encoding="utf-8") as ф:
        правило = " ".join(ф.read().split())
    цитата = ("Слово власника, що міняє продукт, правило, план чи дозвіл, менеджер записує дослівно, з часом UTC, у "
              "`аудит/РІШЕННЯ_ВЛАСНИКА.md` тим самим PR, що й правила, які воно змінює.")
    виняток = ("Слово, що нічого з цього не міняє (відповідь сесії, повтор уже чинного правила, хід роботи), "
               "у журнал не йде й менеджерові не пересилається — його виконує сесія, якій сказано:")
    for назва, текст, коли in (("Кодекс 05:16", КОДЕКС, "2026-11-14T05:16:00Z"),
                              ("ПРОДУКТ", ПРОДУКТ, "2026-11-14T05:17:00Z")):
        with tempfile.TemporaryDirectory() as т:
            записи = [слово(текст, коли), кінець(коли)]
            факт, причина = запуск(т, {}, записи, з_причиною=True)
            умова = факт == "слово"
            if ДО:
                умова = умова and "інакше надішли менеджерові" in причина
            else:
                умова = (умова and цитата in правило and виняток in правило and цитата in причина
                         and виняток in причина and "виконай сам" in причина and "без листа" in причина
                         and "СЛОВО ВЛАСНИКА ГГ:ХХ UTC: <дослівно>" in причина
                         and "інакше надішли менеджерові" not in причина)
            збої += not умова
            print(f"{'ок ' if умова else 'ЗБІЙ'} {назва}: {'вимога листа' if ДО else 'нове правило й два виходи'} → {факт}")
            if текст == ПРОДУКТ:
                записи.insert(1, лист(МЕНЕДЖЕР, f"СЛОВО ВЛАСНИКА 05:17 UTC: «{текст}»", коли))
            факт = запуск(т, {}, записи)
            збої += факт != "пропуск"
            print(f"{'ок ' if факт == 'пропуск' else 'ЗБІЙ'} {назва}: кінець після повернення → {факт}")
            факт = запуск(т, {}, [слово(текст, коли), кінець(коли)])
            збої += факт != "пропуск"
            print(f"{'ок ' if факт == 'пропуск' else 'ЗБІЙ'} {назва}: повтор того самого слова → {факт}")
    if not ДО:
        with tempfile.TemporaryDirectory() as т:
            запуск(т, {}, [слово(КОДЕКС), кінець()])
            факт, причина = запуск(т, {}, [слово(КОДЕКС), слово(ПРОДУКТ), кінець()], з_причиною=True)
            умова = факт == "слово" and "Стилістка" in причина and "Давай більше роботи" not in причина
            збої += not умова
            print(f"{'ок ' if умова else 'ЗБІЙ'} набір слів змінився: лише нове слово → {факт}")
            факт = запуск(т, {}, [слово(ПРОДУКТ), кінець()])
            збої += факт != "пропуск"
            print(f"{'ок ' if факт == 'пропуск' else 'ЗБІЙ'} слово з попереднього набору → {факт}")
    print("збоїв:", збої)
    sys.exit(1 if збої else 0)


main()
