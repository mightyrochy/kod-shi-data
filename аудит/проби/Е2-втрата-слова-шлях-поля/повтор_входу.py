"""МІРИЛО НАРЯДУ `Е2-втрата-слова-шлях-поля`: прилад лічби `корінь_е2_втрата_слова_вхід.py` на записах, де паспорт і вхід
стилістки (`case`/`day` промпта складання) ПЕРЕРАХОВАНІ кодом дерева з тих самих записаних відповідей моделі.

Записи з відповідями моделі (нічний Е1-20261115, живий «як людина» 4): кожен хід розмови — записана відповідь у
`мова({розмова, відповідь_моделі})` → `мова({паспорт_з …})` з паспортом попереднього ходу (як `показ/мовний_шар.js`),
далі `з_показу` → `день_кодами` + `випадок_для_пакета` → `дріт_моделі.випадок` / `день_на_дріт` (як `міст_пакет` і
`дріт_моделі.пакет`). Записи без відповідей моделі (живі 2–3): паспорт — записаний, перераховано лише вхід стилістки
(стадія «читач»). Стадії схеми й моделі прилад бере із записаних промптів і відповідей — їх повтор не міняє.
Сценарій сторінки не записано — порожній (плиток вона не торкалась); суд не перераховано (діагноз — записаний).

Запуск з кореня репозиторію: `python3 аудит/проби/Е2-втрата-слова-шлях-поля/повтор_входу.py [тека джерел]`.
Друкує стадії писача й читача поіменно, таблицю втрат і останнім рядком `писач: N · читач: M`."""
import collections, glob, json, os, sys
КОРІНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
ДЖЕРЕЛА = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.join(КОРІНЬ, 'джерела')
sys.path.insert(0, os.path.join(КОРІНЬ, 'джерела', 'прилади'))
import корінь_е2_втрата_слова_вхід as П                       # прилад — з дерева репозиторію (читає записи)
sys.path.insert(0, ДЖЕРЕЛА)
os.chdir(ДЖЕРЕЛА)
import мовний_шар as М, паспорт_нагоди as ПН, сценарій as СЦ, пакет_моделі as ПМ, дріт_моделі as Д

def хід(відп, її, досі):
    """Одна записана відповідь ходу розмови → паспорт після ходу (None — хід не дав паспорта)."""
    р = json.loads(М.мова({'розмова': {'нове': її[-1], 'історія': []}, 'відповідь_моделі': відп, 'сценарій': {},
                           **({'паспорт': досі} if досі else {})}))
    if р.get('причина') or not р.get('внутрішня'):
        return досі
    d = {'паспорт_з': р['внутрішня'], 'сценарій': {}, 'слова_розмови': її, 'частини': р.get('частини') or {}}
    for к in ('не_взято', 'не_записано'):
        if р.get(к):
            d[к] = р[к]
    if досі:
        d['паспорт'] = досі
    п = json.loads(М.мова(d))
    return п.get('паспорт') or досі

def вхід_стилістки(паспорт):
    сцен, _ = ПН.з_показу({}, паспорт or {})
    день = СЦ.день_кодами(сцен)
    вимоги = ''
    try:
        import міст_вхід as МВ
        вимоги = (МВ.застосувати_паспорт({'паспорт': паспорт, 'сценарій': {}}) or {}).get('вимоги') or ''
    except Exception:
        pass
    в = ПМ.випадок_для_пакета(паспорт, '', сцен, вимоги=вимоги)
    return {'case': Д.випадок(в, день), 'day': Д.день_на_дріт(день, невідоме=True) if день else {}, 'person': {},
            'her_items': ''}

def ходи_нічного(сцена):
    вих = []
    for ф in sorted(glob.glob(os.path.join(П.НІЧНИЙ, сцена, 'VIDPOVIDI', '*хід_розмови*.txt'))):
        т = П._текст(ф)
        п, _, в = т.partition('── ВІДПОВІДЬ')
        her = П.перша_репліка(п)
        if her is not None:
            вих.append((her, в.split('──', 1)[1] if '──' in в else в))
    return вих

def ходи_живого(номер, сцена, прохід):
    ф = os.path.join(П.ПРОБИ, 'живий-як-людина-%d' % номер, 'стенд', 'службове', сцена, 'обміни.jsonl.gz')
    if not os.path.isfile(ф):
        return None
    вих = []
    for р in (json.loads(x) for x in П._рядки_gz(ф)):
        if str(р.get('прохід')) != str(прохід):
            continue
        п = П._промпт_живий(р)
        her = П.перша_репліка(п) if '"her_new_message"' in п else None
        if her is not None:
            вих.append((her, П._відповідь_живий(р)))
    return вих

def перерахувати(з):
    if з['прогін'].startswith('Е1'):
        ходи = ходи_нічного(з['сцена'])
    else:
        ходи = ходи_живого(int(з['прогін'].rsplit('-', 1)[1]), з['сцена'], з['прохід'])
    if ходи:
        її, досі = [], None
        for her, відп in ходи:
            її.append(her)
            досі = хід(відп, list(її), досі)
        з['паспорт'], з['з'] = досі, 'повтор відповідей'
    else:
        з['з'] = 'записаний паспорт'
    if з['паспорт']:
        з['розділи'] = вхід_стилістки(з['паспорт'])
    return з

def головна():
    р, т = П.Реєстри(П.КОРІНЬ), П.читання()
    записи = [перерахувати(з) for з in П.записи_живих() + П.записи_нічного()]
    рядки, _ = П.лічба(записи, т, р)
    зв = П.згорнути(рядки)
    for поле, з in зв.items():
        for ст in ('писач', 'читач'):
            for од in sorted(з['втрата'].get(ст, ())):
                print('%s · %s · %s/%s%s' % (ст, поле, од[0], од[1], (' · «%s»' % од[2]) if од[2] else ''))
    сума = collections.Counter(ст for з in зв.values() for ст, оо in з['втрата'].items() for _ in оо)
    print('втрати: ' + ', '.join('%s %d' % (ст, сума.get(ст, 0)) for ст in П.СТАДІЇ) + '; місць: %d' % П.місць(зв))
    print('писач: %d · читач: %d' % (сума.get('писач', 0), сума.get('читач', 0)))

головна()
