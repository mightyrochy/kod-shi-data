"""Приймання 38/40 після кроку «один колір» (15.11.2026): сукупність, код `main` і вибірка 40 речей нового зерна.

Сукупність — як у прийманні 08.11 (`../річ_колір_приймання_0811/`): кадри дельти перезбору, що змінили колір
(придатний hex ≠ старого, фото в маніфесті), — і, як в оглядах 14.11, лише ті, де вимір стверджує колір: перевимір
#3315 (`перевимір.json.gz`, SAM-кадри ноутбука — `перевимір_SAM.json.gz`) відтворив кадр, і код з виміру на `main`
не «невідомо». Код `main` судять за записом кадру, як `відтворити.py` кроку `../річ_колір_один_колір_1411/`:
`surface.код_розкиду` (Lab і U головного сегмента, множники поправки ≈ середній) і правило кроку #3760 «візерунок не
однотонний — код невідомо». Кадр, якому прогін #3315 коду не дав, Lab у записі не має — його Lab узято з hex
головного сегмента (`lab_з`: на кадрах, де є обидва, код той самий у 415 з 424). Вікна `main` (#3405) не вужчі за
вікна прогону для всіх слів, тож такий кадр може дістати код на `main`. Річ — у сукупності, коли хоч один її кадр
має код; у вибірці — усі такі кадри речі.

    git fetch --depth 1 origin claude/Річ-колір-вимір
    python3 -I аудит/проби/річ_колір_приймання_1511/вибірка.py <тимчасова_тека> [--фото]

`--фото` ще розпаковує фото вибірки з гілки даних у `<тимчасова_тека>/фото`.
"""
import collections, csv, gzip, hashlib, json, random, subprocess, sys
from pathlib import Path

КОРІНЬ = Path(__file__).resolve().parents[3]
ТУТ = Path(__file__).resolve().parent
ДАНІ = "c7b37862c5195f823e0ef211cd8ecd718b498f95"
MAIN = "067155d07bcd5f27d25a0e7b61089ae4a4323ff8"
ЗЕРНО = 20261115
ПЕРЕЗБІР = "аудит/проби/річ_колір_перезбір_0411/"
РОЗКИД = "аудит/проби/річ_колір_розкид_0811/"

ОДИН = r'''
import gzip, json, sys
sys.path.insert(0, sys.argv[1])
import surface as S, колір_простір_перетворення as P
вх = json.load(open(sys.argv[2])); вих = {}
for к, (lab, U, k, візерунок, hx) in вх.items():
    if lab is None:                          # прогін коду не дав — Lab головного сегмента з його hex
        lab = P.to_lab([int(hx[i:i + 2], 16) for i in (1, 3, 5)])
    код, _, чому = S.код_розкиду(tuple(lab), U, [k] * 3 if k else None)
    if код and візерунок != "однотонний":
        код, чому = None, "код невідомо: вимір бачить кілька кольорів речі (%s)" % візерунок
    вих[к] = [код, чому]
json.dump(вих, sys.stdout, ensure_ascii=False)
'''


def git(*а):
    return subprocess.run(["git", "-C", str(КОРІНЬ), *а], check=True, capture_output=True).stdout


def jz(шлях):
    return json.loads(gzip.decompress(git("show", ДАНІ + ":" + шлях)))


def main():
    тмп = Path(sys.argv[1]); тмп.mkdir(parents=True, exist_ok=True)
    дельта, до = jz(ПЕРЕЗБІР + "дельта.json.gz"), jz(ПЕРЕЗБІР + "кадри_ДО.json.gz")["записи"]
    записи, звірка = {}, {}
    for ім in ("перевимір.json.gz", "перевимір_SAM.json.gz"):      # SAM ноутбука переважає, як у `частка.py`
        ч = jz(РОЗКИД + ім)
        for ід, кк in ч["записи"].items():
            for в in кк:
                записи[ід, в["файл"]] = в
        звірка.update(ч["звірка"])
    фото = {(м["id"], м["файл"], м["url"]): м for м in дельта["маніфест"]}
    кадри = []                                   # змінили колір і відтворені
    лік = collections.Counter()
    for ід, кк in sorted(дельта["записи"].items()):
        старі = {в["файл"]: в for в in до.get(ід, [])}
        for в in кк:
            if not (в.get("колір_тип") == "вимір" and в.get("придатна") is True and в.get("hex")
                    and в["hex"] != старі.get(в["файл"], {}).get("hex") and (ід, в["файл"], в["url"]) in фото):
                continue
            лік["змінили колір"] += 1
            з = звірка.get(ід + "|" + в["файл"], {})
            н = записи.get((ід, в["файл"]))
            if not з.get("відтворено") or not н:
                лік["не відтворено"] += 1
                continue
            кадри.append((ід, в, н, з))
    # код main за записом
    вх = {ід + "|" + в["файл"]: [н.get("lab"), з["хрома"][1], з["поправка"], н["вимір"]["візерунок"],
                                 н["вимір"]["сегменти"][0][2]] for ід, в, н, з in кадри}
    json.dump(вх, open(тмп / "вхід.json", "w"))
    тека = тмп / "main"; тека.mkdir(exist_ok=True)
    subprocess.run(["tar", "-x", "-C", str(тека)], input=git("archive", MAIN, "джерела"), check=True)
    коди = json.loads(subprocess.run([sys.executable, "-I", "-W", "ignore", "-c", ОДИН, str(тека / "джерела"),
                                      str(тмп / "вхід.json")], check=True, capture_output=True,
                                     cwd=str(тека / "джерела")).stdout)
    поля = ["id", "файл", "фото", "клас", "маска", "hex", "lab_з", "C", "U", "поправка", "візерунок", "код_прогону",
            "код_main", "чому_main"]
    рядки = []
    for ід, в, н, з in кадри:
        к = ід + "|" + в["файл"]; м = фото[ід, в["файл"], в["url"]]
        рядки.append(dict(id=ід, файл=в["файл"], фото=м["фото"], клас=н.get("клас", ""), маска=н.get("маска", ""),
                          hex=н["вимір"]["сегменти"][0][2], lab_з="запис" if н.get("lab") else "hex", C=з["хрома"][0], U=з["хрома"][1], поправка=з["поправка"],
                          візерунок=н["вимір"]["візерунок"], код_прогону=н["слово"] if н.get("колір_тип") == "вимір" else "невідомо",
                          код_main=коди[к][0] or "невідомо", чому_main=коди[к][1] or "—", sha256=м.get("sha256", "")))
    with open(ТУТ / "сукупність.tsv", "w", encoding="utf-8", newline="") as ф:
        п = csv.DictWriter(ф, fieldnames=поля, delimiter="\t", lineterminator="\n", extrasaction="ignore")
        п.writeheader(); п.writerows(рядки)
    з_кодом = [р for р in рядки if р["код_main"] != "невідомо"]
    речі = sorted({р["id"] for р in з_кодом})
    print("змінили колір: кадрів %d; відтворено перевиміром %d; не відтворено %d" % (
        лік["змінили колір"], len(кадри), лік["не відтворено"]))
    print("речей з кадрами, що змінили колір і відтворені: %d" % len({р["id"] for р in рядки}))
    print("код прогону #3315: кадрів %d" % sum(р["код_прогону"] != "невідомо" for р in рядки))
    print("код main %s: кадрів %d, речей %d; з них кадрів, яким прогін коду не дав, %d" % (
        MAIN[:8], len(з_кодом), len(речі), sum(р["код_прогону"] == "невідомо" for р in з_кодом)))
    print("  коди:", dict(collections.Counter(р["код_main"] for р in з_кодом).most_common()))
    print("  чому невідомо:", dict(collections.Counter(р["чому_main"].split(":")[0] + (
        " (візерунок)" if "кілька кольорів" in р["чому_main"] else "") for р in рядки if р["код_main"] == "невідомо")))
    вибрані = random.Random(ЗЕРНО).sample(речі, min(40, len(речі)))
    вих = []
    for н, ід in enumerate(вибрані, 1):
        for к, р in enumerate([р for р in з_кодом if р["id"] == ід], 1):
            вих.append(dict(номер=н, кадр=к, **р))
    with open(ТУТ / "вибірка.tsv", "w", encoding="utf-8", newline="") as ф:
        п = csv.DictWriter(ф, fieldnames=["номер", "кадр"] + поля + ["sha256"], delimiter="\t", lineterminator="\n")
        п.writeheader(); п.writerows(вих)
    print("зерно %d: речей %d, кадрів %d" % (ЗЕРНО, len(вибрані), len(вих)))
    if "--фото" in sys.argv:
        ф = тмп / "фото"; ф.mkdir(exist_ok=True)
        шляхи = sorted({ПЕРЕЗБІР + р["фото"] for р in вих})
        subprocess.run(["tar", "-x", "-C", str(ф)], input=git("archive", ДАНІ, *шляхи), check=True)
        хибні = [р for р in вих if р["sha256"] and hashlib.sha256((ф / ПЕРЕЗБІР / р["фото"]).read_bytes()).hexdigest()
                 != р["sha256"]]
        print("фото розпаковано: %d, SHA256 не збіглось: %d" % (len(шляхи), len(хибні)))


if __name__ == "__main__":
    main()
