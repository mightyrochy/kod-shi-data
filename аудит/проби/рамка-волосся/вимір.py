"""Вимір кроку Річ-ознаки-обличчя-рамка-волосся: стійкість певного контрасту до рамки волосся.

Запуск із кореня репозиторію (фото — поза репозиторієм, зібрані `набір-портретів/збір.py` і `ворота-щік/збір.py`):
    python -X utf8 аудит/проби/рамка-волосся/вимір.py <тека фото 29> <тека фото 157> [<вихід.json>]

Працює без моделей, відеокарти й OpenCV (рамки бере з уже зафіксованих `ворота-щік/числа.json` і
`ворота-щік/ширший-вимір.json`, sha256 фото звіряє за маніфестами). Перевіряє:
  1) п'ять записаних рамок моделі п09_1 (і без поля, і з полем продукту `ПОЛЕ_ВОЛОССЯ`/`СТОРОНА_ВОЛОССЯ` + `ядро`),
     плюс прохід палітри й запиту стилістки без зупинки (16740);
  2) 28 виміряних кадрів набору (≤4 L*, 21 пара однієї людини) та 11 збурень рамки волосся на кожному кадрі;
  3) 43 виміряні кадри ширшого відбору (≤4 L*, 28 пар) та всі 142 кадри до воріт щік (117 пар) із 11 збуреннями.
"""
