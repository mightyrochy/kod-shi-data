def вирізати(img, рамка, сторона=ПВ.СТОРОНА_ЗОНИ, поле=0.0):
    """Той самий різ, що `пікселіРечіП`: без поля або з полем і `ядро` у тисячних вирізаного кадру."""
    W, H = img.size
    шр, вр = рамка["право"] - рамка["ліво"], рамка["низ"] - рамка["верх"]
    зсув_ш, зсув_в = шр * поле, вр * поле
    л = max(0.0, рамка["ліво"] - зсув_ш)
    в = max(0.0, рамка["верх"] - зсув_в)
    п = min(1000.0, рамка["право"] + зсув_ш)
    н = min(1000.0, рамка["низ"] + зсув_в)
    x0, y0 = round(л / 1000.0 * W), round(в / 1000.0 * H)
    x1, y1 = max(x0 + 1, round(п / 1000.0 * W)), max(y0 + 1, round(н / 1000.0 * H))
    к = img.crop((x0, y0, x1, y1))
    м = min(1.0, сторона / max(к.size))
    к = к.resize((max(1, round(к.size[0] * м)), max(1, round(к.size[1] * м))), Image.LANCZOS)
    вих = {"дані": base64.urlsafe_b64encode(к.tobytes()).decode().rstrip("="), "ширина": к.size[0], "висота": к.size[1]}
    if поле > 0.0:
        вих["ядро"] = {
            "ліво": round((рамка["ліво"] - л) / (п - л) * 1000),
            "верх": round((рамка["верх"] - в) / (н - в) * 1000),
            "право": round((рамка["право"] - л) / (п - л) * 1000),
            "низ": round((рамка["низ"] - в) / (н - в) * 1000),
        }
    return вих


def кадри_зон(img, рамки, з_полем=True):
    """Ріже всі зони портрета так само, як `вимірПортретаП` (`волосся` — з полем `ПОЛЕ_ВОЛОССЯ`, `СТОРОНА_ВОЛОССЯ`)."""
    return {
        ім: вирізати(img, р, ПВ.СТОРОНА_ВОЛОССЯ if (ім == "волосся" and з_полем) else ПВ.СТОРОНА_ЗОНИ,
                     ПВ.ПОЛЕ_ВОЛОССЯ if (ім == "волосся" and з_полем) else 0.0)
        for ім, р in рамки.items()
    }


def заявлені(вим):
    """Продуктові класи з виміру: де певність False — «не певна»."""
    F = МВ.features({"шкіра": ["#808080"], "волосся": ["#808080"], "очі": "#808080", "портрет_вимір": вим})[0]
    кл = ОЗ.класи(F)
    п = F["_meta"]["вимір_портрета"]["певні"]
    return {к: (кл[к] if п[к] else "не певна") for к in кл}


def розбіжні_контрасти(список_класів):
    """Число пар зі спірними певними класами контрасту й загальна кількість пар."""
    пар = розбіжних = 0
    for а, б in itertools.combinations(список_класів, 2):
        пар += 1
        if "не певна" not in (а, б) and а != б:
            розбіжних += 1
    return розбіжних, пар


def збурення_волосся(рамки):
    """11 рамок волосся на тому самому кадрі: вихідна, зсуви ±25/40 % по X і ±20 % по Y, масштаби 0.7/1.3/1.5 і бокова."""
    hb = рамки["волосся"]
    шр, вр = hb["право"] - hb["ліво"], hb["низ"] - hb["верх"]
    центр_ш, центр_в = (hb["ліво"] + hb["право"]) / 2.0, (hb["верх"] + hb["низ"]) / 2.0
    вих = [("оригінал", hb)]
    for назва, sx, sy in (("л25", -0.25, 0), ("п25", 0.25, 0), ("в20", 0, -0.20), ("н20", 0, 0.20),
                          ("л40", -0.40, 0), ("п40", 0.40, 0)):
        нб = {
            "ліво": max(0, min(995, round(hb["ліво"] + шр * sx))),
            "право": max(5, min(1000, round(hb["право"] + шр * sx))),
            "верх": max(0, min(995, round(hb["верх"] + вр * sy))),
            "низ": max(5, min(1000, round(hb["низ"] + вр * sy))),
        }
        if нб["право"] - нб["ліво"] >= 10 and нб["низ"] - нб["верх"] >= 10:
            вих.append((назва, нб))
    for назва, м in (("м07", 0.7), ("м13", 1.3), ("м15", 1.5)):
        нб = {
            "ліво": max(0, min(995, round(центр_ш - шр * м / 2.0))),
            "право": max(5, min(1000, round(центр_ш + шр * м / 2.0))),
            "верх": max(0, min(995, round(центр_в - вр * м / 2.0))),
            "низ": max(5, min(1000, round(центр_в + вр * м / 2.0))),
        }
        if нб["право"] - нб["ліво"] >= 10 and нб["низ"] - нб["верх"] >= 10:
            вих.append((назва, нб))
    щл = рамки["щока_ліва"]
    бік = {
        "ліво": max(0, щл["ліво"] - round(шр * 1.3)),
        "право": max(10, щл["ліво"] - round(шр * 0.1)),
        "верх": max(0, hb["верх"]),
        "низ": min(1000, щл["низ"] + round(вр * 2.5)),
    }
    if бік["право"] - бік["ліво"] >= 20 and бік["низ"] - бік["верх"] >= 20:
        вих.append(("бік_лівий", бік))
    return вих


def перевірити_палітру(вим):
    """Перевіряє, що палітра й запит стилістки працюють без зупинки (16740), коли контраст «не певна»."""
    вх = dict(
        шкіра=[вим["шкіра"]["hex"]], волосся=[вим["волосся"]["hex"]], очі=вим["очі"]["hex"],
        портрет_вимір=вим, зріст=168, без_фото=1, обхвати=dict(плечі=100, груди=92, талія=74, стегна=100),
    )
    пал = json.loads(bridge.виклик("палітри", json.dumps(вх)))
    пр = json.loads(json.loads(bridge.виклик("вибір_палітри", json.dumps(вх)))["промпт"])
    текст = json.dumps(пр, ensure_ascii=False)
    return dict(
        помилка=пал.get("помилка"),
        гілок=len(пал.get("гілки") or []),
        model_hex=текст.count("model_hex"),
        контраст_у_запиті=((пр.get("person") or {}).get("colouring") or {}).get("contrast"),
    )


def виміряти_набір(записи, тека_фото, межа_шуму=4.0, з_полем=True):
    """Міряє всі придатні записи вибірки: оригінал, пари однієї людини та 11 збурень рамки волосся."""
    стара = ПВ.ШУМ_ЗОН_МЕЖА
    if межа_шуму > стара:
        ПВ.ШУМ_ЗОН_МЕЖА = float("inf")
    лишилось_певних = стало_непевних = було_непевних = 0
    по_людях = {}
    збурень_усього = збурень_певних = збурень_пар = збурень_розбіжних = 0
    детерм = True
    try:
        for р in записи:
            if р.get("стан_без_воріт_щік") != "вимір" or р["шум"] > межа_шуму:
                continue
            шлях = тека_фото / (р["кадр"] + ".jpg")
            if hashlib.sha256(шлях.read_bytes()).hexdigest() != р["sha256_фото"]:
                raise ValueError("Контрольна сума не збіглася: " + р["кадр"])
            img = Image.open(шлях).convert("RGB")
            к_ориг = кадри_зон(img, р["рамки"], з_полем=з_полем)
            в1 = ПВ.виміряти(к_ориг)
            if в1 != ПВ.виміряти(к_ориг):
                детерм = False
            if в1["стан"] != "вимір":
                continue
            кл0 = заявлені(в1)
            до_к = р["класи"]["контраст"]
            після_к = кл0["контраст"]
            if до_к != "не певна" and після_к != "не певна":
                лишилось_певних += 1
            elif до_к != "не певна" and після_к == "не певна":
                стало_непевних += 1
            else:
                було_непевних += 1
            по_людях.setdefault(р["людина"], []).append(після_к)

            класи_збурень = [після_к]
            збурень_усього += 1
            if після_к != "не певна":
                збурень_певних += 1
            for назва, рамка_в in збурення_волосся(р["рамки"])[1:]:
                к_зб = dict(к_ориг, волосся=вирізати(img, рамка_в,
                            ПВ.СТОРОНА_ВОЛОССЯ if з_полем else ПВ.СТОРОНА_ЗОНИ,
                            ПВ.ПОЛЕ_ВОЛОССЯ if з_полем else 0.0))
                вз = ПВ.виміряти(к_зб)
                if вз["стан"] != "вимір":
                    continue
                кз = заявлені(вз)["контраст"]
                класи_збурень.append(кз)
                збурень_усього += 1
                if кз != "не певна":
                    збурень_певних += 1
            рз, пз = розбіжні_контрасти(класи_збурень)
            збурень_розбіжних += рз
            збурень_пар += пз
    finally:
        ПВ.ШУМ_ЗОН_МЕЖА = стара

    пар_людей = розбіжних_пар = 0
    for кл_людини in по_людях.values():
        рз, пз = розбіжні_контрасти(кл_людини)
        розбіжних_пар += рз
        пар_людей += пз

    return dict(
        межа=межа_шуму,
        з_полем=з_полем,
        вимірів=лишилось_певних + стало_непевних + було_непевних,
        контраст_лишився_певним=лишилось_певних,
        контраст_став_непевним=стало_непевних,
        контраст_був_непевним=було_непевних,
        пар_однієї_людини=пар_людей,
        розбіжностей_пар_людей=розбіжних_пар,
        збурень_рамок=збурень_усього,
        збурень_певних=збурень_певних,
        збурень_пар=збурень_пар,
        розбіжностей_збурень=збурень_розбіжних,
        детерміновано=детерм,
    )


def головна():
    фото29 = Path(sys.argv[1]) / "портрети"
    фото157 = Path(sys.argv[2]) / "портрети"
    вихід = Path(sys.argv[3]) if len(sys.argv) > 3 else None

    ч29 = json.loads((ВОРОТА / "числа.json").read_text("utf-8"))
    ч142 = json.loads((ВОРОТА / "ширший-вимір.json").read_text("utf-8"))

    # 1. П'ять записаних рамок моделі п09_1 (і з полем продукту, і без поля)
    п09_записи = [р for р in ч29["записи"] if р["кадр"] == "п09_1" and р["спосіб"] == "модель"]
    шлях09 = фото29 / "п09_1.jpg"
    if hashlib.sha256(шлях09.read_bytes()).hexdigest() != п09_записи[0]["sha256_фото"]:
        raise ValueError("Контрольна сума п09_1 не збіглася")
    img09 = Image.open(шлях09).convert("RGB")
    п09_підсумок = {}
    for режим, поле in (("з_полем_продукту", True), ("без_поля", False)):
        деталі = []
        for р in п09_записи:
            к = кадри_зон(img09, р["рамки"], з_полем=поле)
            в = ПВ.виміряти(к)
            кл = заявлені(в)
            пал = перевірити_палітру(в) if поле else None
            деталі.append(dict(
                запис=р["запис"], шум=в["шкіра"]["шум_зон"],
                L_шкіри=в["шкіра"]["lab"][0], L_волосся=в["волосся"]["lab"][0],
                варіанти_L=[t[0] for t in в["волосся"].get("варіанти_рамки") or []],
                контраст_до=р["класи"]["контраст"], контраст_після=кл["контраст"],
                глибина_після=кл["глибина"], детерміновано=(в == ПВ.виміряти(к)),
                палітра=пал,
            ))
        рз, пз = розбіжні_контрасти([x["контраст_після"] for x in деталі])
        п09_підсумок[режим] = dict(пар=пз, розбіжностей=рз, записи=деталі)

    # 2. Відтворюваний набір 29 (≤4 L*, 28 вимірів)
    гео29 = [р for р in ч29["записи"] if р["спосіб"] == "геометрія"]
    набір29 = виміряти_набір(гео29, фото29, межа_шуму=4.0, з_полем=True)

    # 3. Ширший відбір 142: ≤4 L* (43 виміри) та всі 142 (до воріт щік)
    шир43 = виміряти_набір(ч142["записи"], фото157, межа_шуму=4.0, з_полем=True)
    шир142 = виміряти_набір(ч142["записи"], фото157, межа_шуму=24.0, з_полем=True)

    результат = dict(
        межа_продукту=ПВ.ШУМ_ЗОН_МЕЖА,
        поле_волосся=ПВ.ПОЛЕ_ВОЛОССЯ,
        сторона_волосся=ПВ.СТОРОНА_ВОЛОССЯ,
        п09_1_модель=п09_підсумок,
        набір_29_межа4=набір29,
        відбір_142_межа4=шир43,
        відбір_142_усі=шир142,
    )
    if вихід:
        вихід.parent.mkdir(parents=True, exist_ok=True)
        вихід.write_text(json.dumps(результат, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("п09_1 (5 рамок моделі, з полем):", п09_підсумок["з_полем_продукту"]["розбіжностей"], "/",
          п09_підсумок["з_полем_продукту"]["пар"],
          [x["контраст_після"] for x in п09_підсумок["з_полем_продукту"]["записи"]])
    print("п09_1 (5 рамок моделі, без поля):", п09_підсумок["без_поля"]["розбіжностей"], "/",
          п09_підсумок["без_поля"]["пар"],
          [x["контраст_після"] for x in п09_підсумок["без_поля"]["записи"]])
    print("п09_1 палітра (16740):", [(x["палітра"]["помилка"], x["палітра"]["гілок"], x["палітра"]["model_hex"])
                                     for x in п09_підсумок["з_полем_продукту"]["записи"]])
    for назва, блок in (("набір_29_межа4", набір29), ("відбір_142_межа4", шир43), ("відбір_142_усі", шир142)):
        print(f"{назва}: вимірів={блок['вимірів']} (лишилось_певних={блок['контраст_лишився_певним']}, "
              f"стало_непевним={блок['контраст_став_непевним']}, було_непевним={блок['контраст_був_непевним']}), "
              f"пар_людей={блок['пар_однієї_людини']} (розбіжних={блок['розбіжностей_пар_людей']}), "
              f"збурень={блок['збурень_рамок']} ({блок['збурень_пар']} пар, певних={блок['збурень_певних']}, "
              f"розбіжних={блок['розбіжностей_збурень']}), детерм={блок['детерміновано']}")


if __name__ == "__main__":
    головна()
