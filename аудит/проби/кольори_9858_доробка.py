"""Мірило другої спроби 2.14-Г на справжньому мості й тих самих 315 входах.

python аудит/проби/кольори_9858_доробка.py <тека-доказів>
Це замір наряду, не новий гейт. Базові поєднання — запис першої спроби.
"""
import copy
import gzip
import importlib.util
import json
import pathlib
import sys
from collections import Counter

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРІНЬ / "джерела"))
import palettes as П


def головна():
    """Зберігає чипи, поєднання й серіалізовані брифи кожної гілки ДО/ПІСЛЯ."""
    модуль = importlib.util.spec_from_file_location("вимір_9858", pathlib.Path(__file__).with_name("кольори_9858.py"))
    в = importlib.util.module_from_spec(модуль)
    модуль.loader.exec_module(в)
    базові = json.loads(gzip.decompress((КОРІНЬ / "аудит/перевірка/кольори_9858/персони.json.gz").read_bytes()))
    вихід = pathlib.Path(sys.argv[1])
    вихід.mkdir(parents=True, exist_ok=True)
    персони, записи = [], []
    зміни = Counter()
    порожні = Counter()
    пакет_до = в.МО.пакет
    пакети = []
    def запамятати(*арг, **іменовані):
        """Запам'ятовує повернений справжній пакет без підміни його полів."""
        пакет = пакет_до(*арг, **іменовані)
        пакети.append(пакет)
        return пакет
    в.МО.пакет = запамятати
    try:
        for і, до in enumerate(базові):
            пакети.clear()
            після = в.зняти(до["вхід"])
            брифи_до = []
            for г, старі in zip(пакети[-1]["палітри"]["розвилка"], до["поєднання"]):
                практична = copy.copy(г["спец"]["палітра_практична"])
                практична["поєднання"] = старі
                брифи_до.append(П.для_пакета(практична))
            без_аналогової = not any(п["прийом"] == "аналогова" for п in до["поєднання"][0])
            змінено = брифи_до != після["бриф"]
            зміни[("без_аналогової" if без_аналогової else "з_аналоговою") + ("_змінено" if змінено else "_незмінно")] += 1
            for г in після["екран"]["гілки"]:
                if not г["зразки"]:
                    порожні[г["схема"]] += 1
            записи.append(dict(вхід=до["вхід"], бриф_ДО=брифи_до, бриф_ПІСЛЯ=після["бриф"],
                               чипи=після["екран"]["гілки"], поєднання=після["поєднання"],
                               раніше_без_аналогової=без_аналогової, бриф_змінено=змінено))
            персони.append(після)
            if (і + 1) % 35 == 0:
                print(f"Знято {і + 1}/315", flush=True)
    finally:
        в.МО.пакет = пакет_до
    підсумок = dict(в.підсумок(персони), бриф=dict(зміни), порожні_за_схемами=dict(порожні))
    (вихід / "персони.json.gz").write_bytes(gzip.compress(json.dumps(записи, ensure_ascii=False).encode("utf-8"), mtime=0))
    (вихід / "вимір.json").write_text(json.dumps(підсумок, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(підсумок, ensure_ascii=False), flush=True)


if __name__ == "__main__":
    головна()
