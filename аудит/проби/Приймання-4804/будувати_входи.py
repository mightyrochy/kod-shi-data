# Будує два входи кроку `суд` для сцени 17102 — рівно як тест_інваріанти.test_вирок_країв_через_міст_оцінки (дроту нема, лише Python)
import json, sys
sys.path.insert(0, sys.argv[1])
import colorspace
НАЗВИ={"dress_generic":"Синтетична сукня","coat":"Синтетичне пальто","loafers":"Синтетичне взуття"}
def річ(ід, вид, слот, hex_, маска):
    return dict(ід=ід, вид=вид, слот=слот, в_образі=True, принт="однотонний", вимір=dict(lab=colorspace.hx(hex_), hex=hex_, маска=маска), назва=НАЗВИ[вид])
сукня = dict(річ("ф1","dress_generic","сукня","#375647",0.45), довжина="коліно")
пальто = dict(річ("ф2","coat","верхній_шар","#6a594e",0.50), довжина="коліно")
туфлі = річ("ф3","loafers","взуття","#403831",0.15)
вхід = dict(крок="суд", крамниця=False, сценарій_оцінки={"місяць": 11}, зріст=168, обхвати=dict(плечі=98,груди=92,талія=74,стегна=99),
            шкіра=["#edc4ad"], волосся=["#66412f"], очі="#6f7858", пікселі={}, пікселі_фото={})
for ім, дп in (("перевірено", 60), ("граничний-розрив", 70)):
    речі = [dict(сукня, довжина_см=100), dict(пальто, довжина_см=дп), туфлі]
    json.dump(dict(вхід, речі=речі), open(sys.argv[2] + "/" + ім + ".json", "w"), ensure_ascii=False, indent=1)
