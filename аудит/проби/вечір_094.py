# Н-outfit-2-094: «вечір» — факт у полі сценарію, а не підрядок у ноті.
# До правки всі чотири рядки давали престижний_контекст=True (нота про вечір
# пишеться навіть тоді, коли підйом МОВЧИТЬ). Після — лише справді вечірні.
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "джерела"))
import формальність as O  # сценарій/формальність — окремий модуль після поділу `outfit`

ОЧІКУВАНО = [
    (dict(місце="дім", година=20), False),
    (dict(місце="парк", година=19), False),
    # НГ-2 (01.10): назва нагоди часу не дає — код читає виміри (година, місце), не слово
    (dict(нагода="весілля_гість"), False),
    (dict(нагода="весілля_гість", година=19), True),
    (dict(місце="ресторан_високий", година=19), True),
]
збої = 0
for оп, треба in ОЧІКУВАНО:
    с = O.сценарій(**оп)
    в, п = bool(с.get("вечір")), O.престижний_контекст(с)
    ок = (в == треба) and (п is True if треба else п is False)
    збої += not ок
    print("%s %-45s вечір=%-5s престиж=%-5s (треба %s)"
          % ("✓" if ок else "✗", оп, в, п, треба))
print("ВПАЛО %d" % збої)
sys.exit(1 if збої else 0)
