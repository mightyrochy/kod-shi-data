#!/usr/bin/env python3
"""Огляд «повні описи»: 40 випадкових речей, три повні описи (словник, Sonnet, Haiku) під перемішаними літерами. Без мережі й моделей.
Запуск з кореня: python3 аудит/проби/запис-речі-вибірка-300/скрипти/повні.py
Читає дані/{sonnet,haiku}.jsonl, дані/{вибірка,без_фото}.json, каталог_записи_v1.jsonl.gz; пише ohliad-zapysu/повні.json
(без джерел) і дані/ключ_повних.json (ід -> літера -> джерела). Зерно 20261121; повторний запуск дає ті самі файли."""
import gzip, json, os, random, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, "джерела")
from словник_запис import словник
Д = "аудит/проби/запис-речі-вибірка-300/дані/"
ЗЕРНО, К = 20261121, 40
ПОЛЯ = [("тип", "Тип"), ("слот", "Місце в образі"), ("колір", "Колір"), ("родина", "Родина кольору"), ("крій", "Крій"),
        ("довжина", "Довжина"), ("матеріал", "Матеріал"), ("каблук", "Каблук"), ("підошва", "Підошва"), ("сезон", "Сезон"),
        ("формальність", "Формальність")]
СЛОВА = {"верхній_шар": "верхній шар (пальто, куртка, жакет)", "низ": "низ (штани, спідниця)", "верх": "верх (блуза, светр, футболка)",
         "головний_убір": "головний убір", "а-силует": "А-силует", "до_щиколотки": "до щиколотки", "до_стегна": "до стегна",
         "до_коліна": "до коліна", "штучна_шкіра": "штучна шкіра", "деним": "джинс (деним)", "інше": "інший",
         "плаский_до_1_см": "плаский, до 1 см", "низький_1_4_см": "низький, 1–4 см", "середній_4_7_см": "середній, 4–7 см",
         "високий_7_см_і_більше": "високий, 7 см і більше", "груба_рифлена": "груба, рифлена", "тонка": "тонка",
         "всесезонне": "на всі сезони", "демісезон": "демісезон (осінь–весна)", "не_стосується": "не стосується",
         "не видно": "не видно на фото"}
def людське(в):
    if в is None or (isinstance(в, str) and not в.strip()): return "не сказано"
    в = str(в).strip(); return СЛОВА.get(в, в.replace("_", " "))
def розбір(т):
    т = (т or "").strip()
    if т.startswith("```"): т = т.strip("`").lstrip("json").strip()
    try: return json.JSONDecoder().raw_decode(т)[0]
    except Exception: return None
def модельний(з):
    р = з["розб"]; о = {}
    for к, п in (("тип", "тип"), ("слот", "слот"), ("колір", "колір"), ("родина", "родина_кольору"), ("крій", "крій"), ("довжина", "довжина"),
                 ("матеріал", "матеріал"), ("каблук", "каблук"), ("підошва", "підошва"), ("сезон", "сезон"), ("формальність", "формальність")):
        в = (р.get(п) or {}).get("в") if isinstance(р.get(п), dict) else None
        о[к] = людське(в)
    return о
def словниковий(с):
    о = {к: людське(с.get(к)) for к in ("тип", "слот", "крій", "довжина", "матеріал", "каблук", "підошва", "сезон", "формальність")}
    о["колір"] = людське((с.get("_колір_слово") or "").lower() or None); о["родина"] = людське(с.get("колір")); return о
R = {}
for л in gzip.open("каталог_записи_v1.jsonl.gz", "rt", encoding="utf-8"):
    р = json.loads(л)
    if "ід" in р: R[р["ід"]] = р
ЖУРН = {}
for н, ф in (("Sonnet", "sonnet"), ("Haiku", "haiku")):
    ЖУРН[н] = {}
    for л in open(Д + ф + ".jsonl", encoding="utf-8"):
        з = json.loads(л); з["розб"] = розбір(з.get("текст")); ЖУРН[н][з["ід"]] = з
ВИБ = json.load(open(Д + "вибірка.json", encoding="utf-8")); СЛОТ = {в["ід"]: в["слот"] for в in ВИБ}
БЕЗ = set(json.load(open(Д + "без_фото.json", encoding="utf-8")))
придатні = sorted(в["ід"] for в in ВИБ if в["ід"] not in БЕЗ and os.path.exists("ohliad-zapysu/foto/%s.jpg" % в["ід"])
                  and all(ЖУРН[н].get(в["ід"], {}).get("статус") == "ok" and isinstance(ЖУРН[н][в["ід"]]["розб"], dict) for н in ЖУРН))
рнд = random.Random(ЗЕРНО); рнд.shuffle(придатні)
РЕЧІ, КЛЮЧ, дві = [], {}, 0
for ід in придатні:
    if len(РЕЧІ) == К: break
    оп = {"словник": словниковий(словник(R[ід])), "Sonnet": модельний(ЖУРН["Sonnet"][ід]), "Haiku": модельний(ЖУРН["Haiku"][ід])}
    гр = {}
    for дж, о in оп.items(): гр.setdefault(json.dumps([о[к] for к, _ in ПОЛЯ], ensure_ascii=False), []).append(дж)
    if len(гр) == 1: continue
    ключі = list(гр); рнд.shuffle(ключі)
    описи = [json.loads(к) for к in ключі]
    рзн = [len({о[i] for о in описи}) > 1 for i in range(len(ПОЛЯ))]
    РЕЧІ.append({"ід": ід, "назва": R[ід]["назва"][:140], "фото": "foto/%s.jpg" % ід,
                 "описи": [{"л": "АБВ"[i], "поля": [[н, о[j]] for j, (_, н) in enumerate(ПОЛЯ)]} for i, о in enumerate(описи)],
                 "різні": [н for (_, н), р in zip(ПОЛЯ, рзн) if р]})
    КЛЮЧ[ід] = {"АБВ"[i]: гр[к] for i, к in enumerate(ключі)}; дві += len(гр) == 2
json.dump(РЕЧІ, open("ohliad-zapysu/повні.json", "w", encoding="utf-8"), ensure_ascii=False, indent=0)
json.dump(КЛЮЧ, open(Д + "ключ_повних.json", "w", encoding="utf-8"), ensure_ascii=False, indent=0)
сл = {}
for р in РЕЧІ: сл[СЛОТ[р["ід"]]] = сл.get(СЛОТ[р["ід"]], 0) + 1
print("придатних:", len(придатні), "речей:", len(РЕЧІ), "з двома літерами:", дві, "з трьома:", len(РЕЧІ) - дві)
print("за слотом:", dict(sorted(сл.items())))
