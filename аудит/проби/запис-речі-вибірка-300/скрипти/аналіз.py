#!/usr/bin/env python3
"""Лічба проходу: таблиці по полях, розбіжності, сторінка огляду. Запуск з кореня: python3 .../аналіз.py
Читає дані/{sonnet,haiku}.jsonl, дані/вибірка.json, каталог_записи_v1.jsonl.gz; пише дані/зведення.json, дані/таблиці.md,
ohliad-zapysu/картки.json (без джерел варіантів) і дані/ключ_карток.json (літера -> джерела; сторінка його не вантажить)."""
import collections, gzip, json, os, random, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, "джерела")
from словник_запис import словник, ПОЛЯ, a_ok, порожнє, P
from відтінки_кольорів import ВІДТІНКИ
Д = "аудит/проби/запис-речі-вибірка-300/дані/"
ВИБ = json.load(open(Д + "вибірка.json", encoding="utf-8"))
R = {}
for л in gzip.open("каталог_записи_v1.jsonl.gz", "rt", encoding="utf-8"):
    р = json.loads(л)
    if "ід" in р: R[р["ід"]] = р
def розбір(т):
    т = (т or "").strip()
    if т.startswith("```"): т = т.strip("`").lstrip("json").strip()
    try: return json.JSONDecoder().raw_decode(т)[0]
    except Exception: return None
М = {"Sonnet": "sonnet", "Haiku": "haiku"}; ЖУРН = {}
for н, ф in М.items():
    ЖУРН[н] = {}
    for л in open(Д + ф + ".jsonl", encoding="utf-8"):
        з = json.loads(л); ЖУРН[н][з["ід"]] = з; з["розб"] = розбір(з.get("текст"))
ВІДТІНКИ_НАБІР = set(ВІДТІНКИ.values())
СЛ = {в["ід"]: в for в in ВИБ}
СЛОВ = {в["ід"]: словник(R[в["ід"]]) for в in ВИБ}
def знач(н, ід, п):
    о = (ЖУРН[н][ід]["розб"] or {}).get(п)
    if not isinstance(о, dict): return None, None
    return о.get("в"), о.get("дж")
ТАБ = {}   # таблиця 1: поле -> модель -> лічильники
for п in ПОЛЯ:
    ТАБ[п] = {"словник_заповнено": sum(1 for в in ВИБ if (СЛОВ[в["ід"]].get(п) is not None)), "словник_порожньо": 0}
    ТАБ[п]["словник_порожньо"] = len(ВИБ) - ТАБ[п]["словник_заповнено"]
    for н in М:
        л = collections.Counter(); розбіж = 0; порівняно = 0; поза_переліком = 0
        for в in ВИБ:
            ід = в["ід"]; з, дж = знач(н, ід, п); sl = СЛОВ[ід].get(п)
            if з is None: л["нема_відповіді"] += 1; continue
            if з == "не видно" or дж == "не видно": л["не видно"] += 1
            elif з == "не_стосується": л["не_стосується"] += 1
            else:
                л["заповнено"] += 1; л["дж:" + (дж or "?")] += 1
                if п == "колір" and з not in ВІДТІНКИ_НАБІР: поза_переліком += 1
                ск = sl if п != "колір" else sl      # для кольору — родина зі слова крамниці проти родини моделі (нижче)
                if п == "колір":
                    мод = знач(н, ід, "родина_кольору")[0]
                    if sl is not None and мод not in (None, "не видно"): порівняно += 1; розбіж += (мод != sl)
                elif sl is not None:
                    порівняно += 1
                    розбіж += (not a_ok(sl, з)) if п == "тип" else (sl != з)
        л["розбіжність_зі_словником"] = розбіж; л["порівняно"] = порівняно; л["поза_переліком"] = поза_переліком
        ТАБ[п][н] = dict(л)
# Sonnet проти Haiku
РОЗХ = {}
for п in ПОЛЯ:
    c = collections.Counter()
    for в in ВИБ:
        а, _ = знач("Sonnet", в["ід"], п); б, _ = знач("Haiku", в["ід"], п)
        ап, бп = порожнє(а), порожнє(б)
        if ап and бп: c["обидві_порожньо"] += 1
        elif ап != бп: c["одна_порожньо"] += 1
        else: c["обидві_заповнено"] += 1; c["збіг" if ((п == "тип" and a_ok(а, б)) or а == б) else "розходяться"] += 1
    if п == "колір":
        c2 = collections.Counter()
        for в in ВИБ:
            а, _ = знач("Sonnet", в["ід"], "родина_кольору"); б, _ = знач("Haiku", в["ід"], "родина_кольору")
            if а and б: c2["родина_збіг" if а == б else "родина_розходяться"] += 1
        c.update(c2)
    РОЗХ[п] = dict(c)
# сторінка огляду: картки лише там, де джерела розходяться (серед заповнених варіантів — словник, Sonnet, Haiku)
рнд = random.Random(20261120); КАРТКИ = []; КЛЮЧ = {}
ПЕРЕЛІК_ОГЛЯДУ = ["колір", "крій", "довжина", "матеріал", "каблук", "сезон", "слот", "підошва"]
for в in ВИБ:
    ід = в["ід"]
    for п in ПЕРЕЛІК_ОГЛЯДУ:
        var = {}
        if п == "колір":
            sl = СЛОВ[ід].get("_колір_слово")
            if СЛОВ[ід]["колір"]: var["словник"] = sl.lower()
            for н in М:
                з, _ = знач(н, ід, п)
                if not порожнє(з): var[н] = з
            родини = {"словник": СЛОВ[ід]["колір"]}
            for н in М: родини[н] = знач(н, ід, "родина_кольору")[0]
            значущі = {к: родини[к] for к in var if родини.get(к)}
            if len(set(значущі.values())) < 2: continue
        else:
            if СЛОВ[ід].get(п): var["словник"] = СЛОВ[ід][п]
            for н in М:
                з, _ = знач(н, ід, п)
                if not порожнє(з): var[н] = з
            if len(set(var.values())) < 2: continue
        за_текстом = collections.defaultdict(list)
        for к, з in var.items(): за_текстом[з].append(к)
        тексти = list(за_текстом); рнд.shuffle(тексти)
        літери = "АБВГ"
        КАРТКИ.append({"ід": ід, "поле": п, "назва": R[ід]["назва"][:110], "фото": "foto/%s.jpg" % ід,
                       "варіанти": [{"л": літери[i], "текст": т} for i, т in enumerate(тексти)]})
        КЛЮЧ["%s|%s" % (ід, п)] = {літери[i]: за_текстом[т] for i, т in enumerate(тексти)}
os.makedirs("ohliad-zapysu", exist_ok=True)
json.dump(КАРТКИ, open("ohliad-zapysu/картки.json", "w", encoding="utf-8"), ensure_ascii=False)
json.dump(КЛЮЧ, open(Д + "ключ_карток.json", "w", encoding="utf-8"), ensure_ascii=False, indent=0)
# витрата
ЦІНИ = {"Sonnet": (2.0, 10.0), "Haiku": (0.10, 0.50)}; БАЗА = {"Sonnet": 1465, "Haiku": 1485}; КАТАЛОГ = 28890
ВИТР = {}
for н in М:
    Л = list(ЖУРН[н].values()); k = len(Л)
    вх = sum(з["вхід_нових"] + з["вхід_кеш_запис"] + з["вхід_кеш_читання"] for з in Л) / k - БАЗА[н]
    вих = sum(з["вихід"] for з in Л) / k; дум = sum((з.get("думки") or 0) for з in Л) / k
    секунд = sum(з["с"] for з in Л) / k
    ціна_речі = (вх * ЦІНИ[н][0] + вих * ЦІНИ[н][1]) / 1e6
    ВИТР[н] = {"речей": k, "вхід_на_річ": round(вх), "вихід_на_річ": round(вих), "з_них_думки": round(дум), "секунд_на_річ": round(секунд, 1),
               "ціна_речі_usd": ціна_речі, "каталог_речей": КАТАЛОГ, "ціна_каталогу_usd": ціна_речі * КАТАЛОГ, "збоїв": sum(1 for з in Л if з["статус"] != "ok"),
               "без_розбору": sum(1 for з in Л if з["розб"] is None)}
json.dump({"поля": ТАБ, "розходження": РОЗХ, "витрата": ВИТР, "карток": len(КАРТКИ),
           "карток_за_полем": dict(collections.Counter(к["поле"] for к in КАРТКИ))}, open(Д + "зведення.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
print(json.dumps({"витрата": ВИТР, "карток": len(КАРТКИ), "за_полем": dict(collections.Counter(к["поле"] for к in КАРТКИ))}, ensure_ascii=False, indent=1))
