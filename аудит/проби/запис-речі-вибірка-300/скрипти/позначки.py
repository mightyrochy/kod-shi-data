#!/usr/bin/env python3
"""Зведення сліпих позначок (наряд «Запис-речі-позначки-наосліп»): числа звіту ПОЗНАЧКИ.md і перелік карток для людини.
Запуск з кореня: python3 аудит/проби/запис-речі-вибірка-300/скрипти/позначки.py claude
Читає дані/позначки_<хто>.json (формат кнопки «Скопіювати всі відповіді»), дані/позначки_<хто>_додаток.json («не певна» і повтор
30 карток), дані/ключ_карток.json; пише ohliad-zapysu/людині.json (перелік «<ід>|<поле>» для сторінки з ?список=людині) і
друкує таблиці. Точність по джерелах — тим самим скриптом точність.py (на всіх позначках і лише на певних)."""
import collections, json, os, subprocess, sys, tempfile
Д = "аудит/проби/запис-речі-вибірка-300/"
хто = sys.argv[1] if len(sys.argv) > 1 else "claude"
В = json.load(open(Д + f"дані/позначки_{хто}.json", encoding="utf-8"))
Дод = json.load(open(Д + f"дані/позначки_{хто}_додаток.json", encoding="utf-8"))
К = json.load(open(Д + "дані/ключ_карток.json", encoding="utf-8"))
Картки = json.load(open("ohliad-zapysu/картки.json", encoding="utf-8"))
НП = set(Дод["не_певна"]); ПОЛЯ = sorted({к["поле"] for к in Картки})
assert set(В) == {к["ід"] + "|" + к["поле"] for к in Картки}, "позначено не всі картки або зайві"
ключ = lambda к: к["ід"] + "|" + к["поле"]
def джерело(кл, дж):
    return next((л for л, д in К[кл].items() if дж in д), None)

def точність(відповіді):
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as ф:
        json.dump(відповіді, ф, ensure_ascii=False)
    try:
        return subprocess.run([sys.executable, Д + "скрипти/точність.py", ф.name], capture_output=True, text=True, check=True).stdout
    finally:
        os.unlink(ф.name)

print("## Точність на всіх 295 позначках (точність.py)\n"); print(точність(В))
print("## Точність лише на певних позначках (без «не певна»)\n"); print(точність({к: в for к, в in В.items() if к not in НП}))

print("## Позначки по полях\n\n| поле | карток | літера | з них «не певна» | «жодне» | «на фото не видно» | «не певна» всього |\n|---|---|---|---|---|---|---|")
р = collections.defaultdict(collections.Counter)
for к in Картки:
    кл, п = ключ(к), к["поле"]; в = В[кл]; р[п]["карток"] += 1
    р[п]["жодне" if в == "жодне" else "не видно" if в == "не видно" else "літера"] += 1
    if кл in НП: р[п]["НП"] += 1; р[п]["НП-літера"] += в not in ("жодне", "не видно")
сум = collections.Counter()
for п in ПОЛЯ + ["усього"]:
    x = сум if п == "усього" else р[п]
    if п != "усього": сум.update(р[п])
    print(f"| {п} | {x['карток']} | {x['літера']} | {x['НП-літера']} | {x['жодне']} | {x['не видно']} | {x['НП']} |")

print("\n## Кожна модель по полях: перевірено картками (влучила / ні / «не видно» у позначці)\n")
print("| поле | джерело | на картках | влучило | не влучило (певна позначка) | не влучило (не певна) | позначка «не видно» |\n|---|---|---|---|---|---|---|")
for п in ПОЛЯ:
    for дж in ("словник", "Sonnet", "Haiku"):
        c = collections.Counter()
        for к in Картки:
            if к["поле"] != п: continue
            кл = ключ(к); л = джерело(кл, дж)
            if л is None: continue
            c["на"] += 1; в = В[кл]
            if в == "не видно": c["нв"] += 1
            elif в == л: c["так"] += 1
            elif кл in НП: c["ні_нп"] += 1
            else: c["ні"] += 1
        print(f"| {п} | {дж} | {c['на']} | {c['так']} | {c['ні']} | {c['ні_нп']} | {c['нв']} |")

проти = []
for к in Картки:
    кл = ключ(к); в = В[кл]
    if в == "не видно": continue
    s, h = джерело(кл, "Sonnet"), джерело(кл, "Haiku")
    if (s or h) and в != s and в != h: проти.append(кл)
людині = [ключ(к) for к in Картки if ключ(к) in НП or ключ(к) in проти]
json.dump(людині, open("ohliad-zapysu/людині.json", "w", encoding="utf-8"), ensure_ascii=False, indent=0)
print(f"\n## Людині\n\n«не певна» {len(НП)}, проти обох моделей {len(проти)} (з них певних {len(set(проти) - НП)}), разом {len(людині)} карток → ohliad-zapysu/людині.json")
print("по полях:", dict(collections.Counter(к.split('|')[1] for к in людині)))
print("проти обох моделей, певні:", sorted(set(проти) - НП))

П = Дод["повтор"]; однак = [к for к in П["відповіді"] if П["відповіді"][к] == В[к]]
інакше = [к for к in П["відповіді"] if к not in однак]
print(f"\n## Повтор\n\nоднаково {len(однак)} з {len(П['відповіді'])}; різні: " + "; ".join(
    f"{к}: {В[к]}{' (не певна)' if к in НП else ''} → {П['відповіді'][к]}{' (не певна)' if к in П['не_певна'] else ''}" for к in інакше))
print("різні серед певних у першому проході:", sum(к not in НП for к in інакше))
