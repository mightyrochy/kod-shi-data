#!/usr/bin/env python3
"""Добір 300 речей: спершу ті, що йшли в образи 8 ситуацій третього й четвертого живих прогонів (склад образів у verdykty-*.json),
далі — до 300 порівну за слотами; обов'язково шарф, штани й пасок з трьох вад і десять речей із таблицею мірок.
Запуск з кореня репозиторію: python3 аудит/проби/запис-речі-вибірка-300/скрипти/вибірка.py"""
import glob, gzip, json, random, re, collections, os
КОРІНЬ = "аудит/проби/"; ВИХІД = КОРІНЬ + "запис-речі-вибірка-300/дані/вибірка.json"
R = {}
for л in gzip.open("каталог_записи_v1.jsonl.gz", "rt", encoding="utf-8"):
    р = json.loads(л)
    if "ід" in р: R[р["ід"]] = р
def P(р, к):
    for п in р["параметри"]:
        if п[0] == к: return п[1]
def слот(р):
    return P(р, "слот") or {"1": "сукня", "2": "верх", "3": "верхній_шар", "4": "низ", "5": "прикраси", "6": "головний_убір",
                              "7": "сумка", "8": "шарф", "9": "пояс", "10": "взуття"}.get(р["категорія"], "без розділу")
ГРУПА = lambda с: "прикраси" if с in ("прикраси", "сережки", "намисто", "брошка", "браслет", "каблучка", "кольє") else с
показ = collections.OrderedDict()
for ран in ("живий-як-людина-4", "живий-як-людина-3"):
    for ф in sorted(glob.glob(КОРІНЬ + ран + "/с*/verdykty*.json")):
        д = json.load(open(ф, encoding="utf-8")); с = ф.split("/")[-2][:2]
        for пр in д["прогони"]:
            for в in пр["вердикти"]:
                for і in (в.get("склад") or "").split("+"):
                    ід = і.split("@")[0]
                    if ід in R: показ.setdefault(ід, set()).add(ран[-1] + с + "р" + str(в["рука"]))
ОБОВ = ["ж53-ad5d09959ece61bbe2bf", "ж-05797", "ж-08574"]   # шарф, штани, пасок з вад четвертого прогону
def кадри(р): return [к for к in р["кадри"] if k_ok(к)]
def k_ok(к): return к.startswith("http")
ВИКЛ = set(json.load(open(КОРІНЬ + "запис-речі-вибірка-300/дані/без_фото.json"))) if os.path.exists(КОРІНЬ + "запис-речі-вибірка-300/дані/без_фото.json") else set()
ВИКЛ_МАГ = {P(R[і], "магазин") for і in ВИКЛ if і in R}   # магазини, чиї фото з хмарного середовища не віддаються (503/403)
def придатна(р): return р["ід"] not in ВИКЛ and P(р, "магазин") not in ВИКЛ_МАГ and bool(кадри(р)) and р["доступність"] == "true" and слот(р) not in ("без розділу", "білизна", "шкарпетки")
рнд = random.Random(300)
вибрані = collections.OrderedDict((і, "образ") for і in ОБОВ)
for і in показ:
    if придатна(R[і]): вибрані.setdefault(і, "образ")
# мірки: десять речей із таблицею, де є «Довжина виробу» чи обхват; бажано з показаних
def мірки_ок(р):
    т = P(р, "таблиця_мірок") or ""
    return придатна(р) and ("Довжина виробу" in т or "Обхват" in т) and len(т) < 1500 and слот(р) in ("сукня", "верх", "низ", "верхній_шар")
кандидати_мірок = [і for і, р in R.items() if мірки_ок(р)]
в_мірках = [і for і in вибрані if мірки_ок(R[і])]
рнд.shuffle(кандидати_мірок)
мірки = list(в_мірках[:10])
for і in кандидати_мірок:
    if len(мірки) >= 10: break
    if і not in мірки: мірки.append(і); вибрані.setdefault(і, "мірки")
# добір до 300 порівну за слотами
гр = collections.Counter(ГРУПА(слот(R[і])) for і in вибрані)
ГРУПИ = ["верх", "низ", "сукня", "комплект", "верхній_шар", "взуття", "сумка", "головний_убір", "пояс", "шарф", "прикраси"]
пул = collections.defaultdict(list)
for і, р in R.items():
    if і not in вибрані and придатна(р) and ГРУПА(слот(р)) in ГРУПИ: пул[ГРУПА(слот(р))].append(і)
for г in пул: рнд.shuffle(пул[г])
while len(вибрані) < 300:
    г = min((г for г in ГРУПИ if пул[г]), key=lambda г: гр[г])
    і = пул[г].pop(); вибрані[і] = "добір"; гр[г] += 1
вих = []
for і, чому in вибрані.items():
    р = R[і]; вих.append({"ід": і, "чому": чому, "в_образах": sorted(показ.get(і, [])), "слот": слот(р), "група": ГРУПА(слот(р)),
                         "мірки": і in мірки})
json.dump(вих, open(ВИХІД, "w", encoding="utf-8"), ensure_ascii=False, indent=0)
print(len(вих), collections.Counter(в["чому"] for в in вих), collections.Counter(в["група"] for в in вих), sum(в["мірки"] for в in вих))
