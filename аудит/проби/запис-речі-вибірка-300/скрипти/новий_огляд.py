def людське_значення(поле, з):
    """Значення мітки нового запису → слова для власника; коди внутрішньої мови — їхні українські ключі."""
    в = з["значення"]
    if в == "не_певний":
        а, б = з["межі"][0], з["межі"][-1]
        return f"не певно: {а}–{б} см" if поле == "каблук" else f"не певно: {а}–{б}"
    if поле == "каблук":
        return "без каблука" if в == 0 else f"{в:g} см"
    if поле == "утеплення" and в == "warm":
        return "тепле"
    if isinstance(в, list):
        return ", ".join(людське_значення(поле, {"значення": х}) for х in в)
    for шлях in мітки.МІТКИ[поле].get("реєстр", ()):
        if шлях[:2] == ["внутрішня_мова", "ТАБЛИЦЯ"] and в in ТАБЛИЦЯ[шлях[2]] and в not in СЛОВА:
            return ТАБЛИЦЯ[шлях[2]][в].replace("_", " ")
    return СЛОВА.get(в, str(в).replace("_", " "))


def новий_рядок(запис, слот):
    """Новий запис моделі → (текст опису, поля [[назва, значення]]) лише з міток, застосовних до слоту речі."""
    розб = запис_речі.розібрати(запис.get("текст"))
    слот = (розб["мітки"].get("слот") or {}).get("значення", слот)
    поля = []
    for поле in мітки.ЗАПИТАНІ:
        if not мітки.застосовна(поле, слот):
            continue
        з = розб["мітки"].get(поле)
        if з is None:
            поля.append([НАЗВИ[поле], "невідомо"])
            continue
        поля.append([НАЗВИ[поле], людське_значення(поле, з) + f" · {ДЖЕРЕЛО[з['джерело']]}"])
    return розб["опис"], поля


def старий_вибір(ід, ключ, відповідь):
    """Яке старе джерело обрав власник 21.11 і з якої підстави (правило — у шапці)."""
    вибір = (відповідь or {}).get("вибір", "")
    if вибір in ключ:
        return ключ[вибір][0], f"вибір 21.11: {вибір}"
    літери = [л for л in (відповідь or {}).get("коментар", "") if л in ключ]
    for л in літери:
        if ключ[л][0] != "словник":
            return ключ[л][0], f"коментар 21.11 називає {' '.join(літери)}"
    return "Sonnet", f"вибору 21.11 нема ({вибір or 'порожньо'}): старий Sonnet"


