def старе_людське(в):
    if в is None or (isinstance(в, str) and not в.strip()):
        return "не сказано"
    в = str(в).strip()
    return СТАРІ_СЛОВА.get(в, в.replace("_", " "))


def модельний(запис):
    т = (запис.get("текст") or "").strip()
    if т.startswith("```"):
        т = т.strip("`").removeprefix("json").strip()
    try:
        р = json.JSONDecoder().raw_decode(т)[0]
    except ValueError:
        р = {}
    п = {"родина": "родина_кольору"}
    return {к: старе_людське((р.get(п.get(к, к)) or {}).get("в") if isinstance(р.get(п.get(к, к)), dict) else None)
            for к, _ in ПОЛЯ_СТАРІ}


def словниковий_рядок(рядок):
    с = словник(рядок)
