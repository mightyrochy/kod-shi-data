#!/usr/bin/env python3
"""Підсумок огляду «повні описи»: python3 .../повні_підсумок.py <файл з відповідями, JSON зі сторінки>
За дані/ключ_повних.json рахує, скількох разів обрано словник, Sonnet, Haiku, «однаково», «жоден»; друкує коментарі з назвою речі й тим,
чий опис обрано. Коли літеру ділять два джерела (однакові описи), кожному — по частці 1/2 (у стовпці «по літері» — повний голос)."""
import json, sys
Д = "аудит/проби/запис-речі-вибірка-300/дані/"
КЛЮЧ = json.load(open(Д + "ключ_повних.json", encoding="utf-8"))
НАЗВИ = {р["ід"]: р["назва"] for р in json.load(open("ohliad-zapysu/повні.json", encoding="utf-8"))}
В = json.load(open(sys.argv[1], encoding="utf-8"))
лічба = {"словник": 0.0, "Sonnet": 0.0, "Haiku": 0.0}; повних = {"словник": 0, "Sonnet": 0, "Haiku": 0}; однаково = жоден = без = 0; ком = []
for ід, в in В.items():
    if ід not in КЛЮЧ: print("невідома річ:", ід); continue
    вибір, к = (в.get("вибір") or ""), (в.get("коментар") or "").strip()
    чий = "—"
    if вибір in КЛЮЧ[ід]:
        дж = КЛЮЧ[ід][вибір]; чий = "+".join(дж)
        for д in дж: лічба[д] += 1 / len(дж); повних[д] += 1
    elif вибір == "однаково": однаково += 1; чий = "однаково точні"
    elif вибір == "жоден": жоден += 1; чий = "жоден не годиться"
    else: без += 1
    if к: ком.append((ід, НАЗВИ.get(ід, "?"), вибір or "без вибору", чий, к))
print("позначено:", sum(1 for в in В.values() if в.get("вибір")), "із", len(КЛЮЧ), "· без вибору (лише коментар):", без)
print("%-10s %8s %10s" % ("джерело", "частка", "по літері"))
for д in лічба: print("%-10s %8.1f %10d" % (д, лічба[д], повних[д]))
print("однаково точні:", однаково, "· жоден не годиться:", жоден)
print("\nКоментарі (%d):" % len(ком))
for ід, н, в, ч, к in ком: print("- %s «%s» · вибір %s · обрано: %s\n    %s" % (ід, н[:70], в, ч, к))
