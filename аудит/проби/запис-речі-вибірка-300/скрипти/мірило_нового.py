#!/usr/bin/env python3
"""Мірило наряду Запис-речі-новий-вид (б)–(г): запис нового виду проти старого на тій самій вибірці 300.

Запуск з кореня (без мережі й моделей):
  python3 аудит/проби/запис-речі-вибірка-300/скрипти/мірило_нового.py                — числа (б), (в), (г)
  python3 …/мірило_нового.py --очима-таблиця <файл.json>                                 — таблиця для перевірки очима
(б) Частка «невідомо» для входів взуття й тепла — підошва, каблук, матеріал верху (взуття), водостійкість (взуття,
    верхній шар), утеплення (взуття, верхній шар, головний убір) — ДО: журнали 21.11 (`дані/{sonnet,haiku}.jsonl`) і запис
    живого каталогу, як його читає Ч2 (`річ.читати` рядка таблиці каталогу); ПІСЛЯ: `дані/{sonnet,haiku}_новий.jsonl`.
    Слот — з вибірки (`дані/вибірка.json`). «Не певний» з межами — відоме з межами, рахується окремо. Хибні відомі
    значення — з вердиктів очима (`дані/очима.json`: ід → «<запис>|<поле>» → так | ні | не видно), якщо файл є.
(в) Частка «охайна» й «демісезон» на 40 речах огляду 21.11 (`дані/ключ_повних.json`): ДО — старі записи Sonnet, Haiku;
    ПІСЛЯ — ошатність «neat» і сезон рівно {cool, mild} (найближче до «демісезону» в смугах погоди) та «невідомо».
(г) Токени на кандидата в запиті складання Ч4 на записаній сцені с5 (`ядро/тести/обвязка.вхід_с5`): каталог — рядки
    вибірки з живої таблиці каталогу (ДО) і ті самі рядки з ключем `мітки_речі` (ПІСЛЯ); міра — оцінка ядра
    (`палітрові_знання().оцінити_текст_ядра`) рядків пулу, поділена на кількість кандидатів.
Таблицю каталогу збирає той самий шлях, що й тест Ч2 (`тест_н2`, `каталог_повний.xml.gz`): ~2,5 хв; кеш — /tmp.
"""
import json
import os
import pickle
import sys
from collections import Counter
from pathlib import Path
from shutil import copyfile
from tempfile import TemporaryDirectory

КОРІНЬ = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(КОРІНЬ / "джерела"))
import запис_речі  # noqa: E402
from ядро import мітки, річ  # noqa: E402
from ядро.поняття import НЕВІДОМО, НЕ_ПЕВНИЙ  # noqa: E402

Д = КОРІНЬ / "аудит/проби/запис-речі-вибірка-300/дані"
КЕШ = Path("/tmp/каталог_рядки.pkl")
ВХОДИ = {"підошва": ("взуття",), "каблук": ("взуття",), "матеріал_верху": ("взуття",),
         "водостійкість": ("взуття", "верхній_шар"), "утеплення": ("взуття", "верхній_шар", "головний_убір")}
ПОЛЕ_МІТКИ = {"матеріал_верху": "тканина"}
СТАРЕ_ПОЛЕ = {"матеріал_верху": "матеріал", "підошва": "підошва", "каблук": "каблук"}
СТАРЕ_НЕВІДОМЕ = (None, "", "не видно", "невідомо", "unknown", "не_стосується", "не сказано")


def _старий_розбір(текст):
    т = (текст or "").strip()
    if т.startswith("```"):
        т = т.strip("`").removeprefix("json").strip()
    try:
        р = json.JSONDecoder().raw_decode(т)[0]
    except ValueError:
        return {}
    return р if isinstance(р, dict) else {}


def _журнал(назва):
    вихід = {}
    for л in open(Д / f"{назва}.jsonl", encoding="utf-8"):
        з = json.loads(л)
        if з.get("статус") == "ok":
            вихід.setdefault(з["ід"], з)
    return вихід


def каталог():
    """Рядки таблиці каталогу, як їх вкладає збірка (той самий шлях, що `тест_н2`), за ід вибірки."""
    if not КЕШ.exists():
        import feed
        import фід_розбір
        import таблиця_каталогу
        import таблиця_збирання
        архів = КОРІНЬ / "каталог_повний.xml.gz"
        with TemporaryDirectory() as тека:
            copyfile(архів, Path(тека) / архів.name)
            шлях = feed.каталог_на_диску(str(Path(тека) / архів.stem))
            таблиця = таблиця_збирання.зібрати(шлях, str(КОРІНЬ / "джерела"))
            рядки = таблиця_каталогу.відновити(таблиця, фід_розбір.офери_фіду(шлях))["каталог"]
        pickle.dump(рядки, КЕШ.open("wb"))
    return {р["id"].split("@")[0]: р for р in pickle.load(КЕШ.open("rb"))}


def значення_до_журналу(запис, вхід):
    if вхід not in СТАРЕ_ПОЛЕ:
        return НЕВІДОМО  # поля в старому записі не було
    в = _старий_розбір(запис.get("текст")).get(СТАРЕ_ПОЛЕ[вхід])
    в = в.get("в") if isinstance(в, dict) else в
    return НЕВІДОМО if в in СТАРЕ_НЕВІДОМЕ else в


def значення_до_каталогу(рядок, вхід):
    if рядок is None:
        return None
    факт = річ.читати(рядок).поля.get(ПОЛЕ_МІТКИ.get(вхід, вхід))
    if факт is None or факт.значення in (НЕВІДОМО, None):
        return НЕВІДОМО
    return f"{НЕ_ПЕВНИЙ} {факт.межі}" if факт.значення == НЕ_ПЕВНИЙ else факт.значення


def значення_після(запис, вхід):
    м = запис_речі.розібрати(запис.get("текст"))["мітки"].get(ПОЛЕ_МІТКИ.get(вхід, вхід))
    if м is None:
        return НЕВІДОМО
    return f"{НЕ_ПЕВНИЙ} {м['межі']}" if м["значення"] == НЕ_ПЕВНИЙ else м["значення"]


def записи_вибірки():
    """ід → {запис → {вхід → значення}} для всіх застосовних входів (б)."""
    слоти = {в["ід"]: в["слот"] for в in json.load(open(Д / "вибірка.json", encoding="utf-8"))}
    журнали = {н: _журнал(ф) for н, ф in (("ДО Sonnet 21.11", "sonnet"), ("ДО Haiku 21.11", "haiku"),
                                          ("ПІСЛЯ Sonnet", "sonnet_новий"), ("ПІСЛЯ Haiku", "haiku_новий"))}
    рядки = каталог()
    вихід = {}
    for ід, слот in слоти.items():
        входи = [в for в, с in ВХОДИ.items() if слот in с]
        if not входи:
            continue
        з = {}
        for н, ж in журнали.items():
            if ід in ж:
                f = значення_після if н.startswith("ПІСЛЯ") else значення_до_журналу
                з[н] = {в: f(ж[ід], в) for в in входи}
        if ід in рядки:
            з["ДО каталог"] = {в: значення_до_каталогу(рядки[ід], в) for в in входи}
        вихід[ід] = {"слот": слот, "записи": з}
    return вихід


def мірило_б(записи):
    очима_файл = Д / "очима.json"
    очима = json.load(open(очима_файл, encoding="utf-8")) if очима_файл.exists() else {}
    рядки = []
    for запис in ("ДО Sonnet 21.11", "ДО Haiku 21.11", "ДО каталог", "ПІСЛЯ Sonnet", "ПІСЛЯ Haiku"):
        for вхід in ВХОДИ:
            знач = [(ід, р["записи"][запис][вхід]) for ід, р in записи.items()
                    if запис in р["записи"] and вхід in р["записи"][запис]]
            н = len(знач)
            нев = sum(в == НЕВІДОМО for _, в in знач)
            межі = sum(isinstance(в, str) and в.startswith(НЕ_ПЕВНИЙ) for _, в in знач)
            вердикти = Counter(очима.get(ід, {}).get(f"{запис}|{вхід}") for ід, в in знач if в != НЕВІДОМО)
            перевірено = вердикти["так"] + вердикти["ні"] + вердикти["не видно"]
            рядки.append({"запис": запис, "вхід": вхід, "речей": н, "невідомо": нев,
                          "частка_невідомо": round(нев / н, 3) if н else None, "не_певний": межі,
                          "відомих": н - нев, "перевірено_очима": перевірено, "хибних": вердикти["ні"],
                          "не_видно": вердикти["не видно"],
                          "частка_хибних": round(вердикти["ні"] / перевірено, 3) if перевірено else None})
    return рядки


def мірило_в():
    ід40 = list(json.load(open(Д / "ключ_повних.json", encoding="utf-8")))
    вихід = {}
    for назва, файл in (("ДО Sonnet 21.11", "sonnet"), ("ДО Haiku 21.11", "haiku")):
        ж = _журнал(файл)
        ф = Counter(str((_старий_розбір(ж[і]["текст"]).get("формальність") or {}).get("в")) for і in ід40)
        с = Counter(str((_старий_розбір(ж[і]["текст"]).get("сезон") or {}).get("в")) for і in ід40)
        вихід[назва] = {"охайна": ф["охайна"], "демісезон": с["демісезон"], "з": len(ід40)}
    for назва, файл in (("ПІСЛЯ Sonnet", "sonnet_новий"), ("ПІСЛЯ Haiku", "haiku_новий")):
        ж = _журнал(файл)
        ф, с, сн, фн = 0, 0, 0, 0
        for і in ід40:
            м = запис_речі.розібрати(ж[і]["текст"])["мітки"]
            ош, сез = м.get("ошатність"), м.get("сезон_тканини")
            ф += bool(ош and ош["значення"] == "neat")
            фн += ош is None
            с += bool(сез and sorted(сез["значення"]) == ["cool", "mild"])
            сн += сез is None
        вихід[назва] = {"охайна (neat)": ф, "ошатність невідомо": фн, "демісезон ({cool, mild})": с,
                        "сезон невідомо (зокрема прикраси, сумки, пояси — мітки нема)": сн, "з": len(ід40)}
    return вихід


def мірило_г():
    from ядро import протокол
    from ядро import знання
    from ядро.тести import обвязка
    рядки = каталог()
    ід = [в["ід"] for в in json.load(open(Д / "вибірка.json", encoding="utf-8")) if в["ід"] in рядки]
    оцінити = знання.палітрові_знання().оцінити_текст_ядра
    вихід = {}
    for назва, файл in (("ДО", None), ("ПІСЛЯ Sonnet", "sonnet_новий"), ("ПІСЛЯ Haiku", "haiku_новий")):
        ж = _журнал(файл) if файл else {}
        кат = []
        for і in ід:
            р = dict(рядки[і])
            if і in ж:
                розб = запис_речі.розібрати(ж[і]["текст"])
                р["мітки_речі"] = {"опис": розб["опис"], "мітки": розб["мітки"]}
            кат.append(р)
        в = обвязка.почати(протокол, обвязка.вхід_с5(каталог=кат))
        запит = next(з for з in в["запити"] if з["вид"] == "складання")
        тіло = json.loads(запит["модель"]["messages"][0]["content"])
        пул = тіло["pool"]
        к = len(пул["rows"])
        пул_т = оцінити(json.dumps(пул["rows"], ensure_ascii=False, separators=(",", ":")))
        опис_т = 0
        if "description" in пул["cols"]:
            і_оп = пул["cols"].index("description")
            опис_т = оцінити(json.dumps([р[і_оп] for р in пул["rows"]], ensure_ascii=False, separators=(",", ":")))
        вихід[назва] = {"кандидатів": к, "токенів_пулу": пул_т, "на_кандидата": round(пул_т / к, 1) if к else None,
                        "з_них_опис_на_кандидата": round(опис_т / к, 1) if к else None,
                        "колонок": len(пул["cols"]), "токенів_запиту": оцінити(запит["модель"]["messages"][0]["content"])}
    return вихід


def очима_таблиця(шлях):
    """Таблиця перевірки очима: взуття й верхні шари вибірки, відомі значення кожного запису, слова крамниці, фото."""
    import gzip
    записи = записи_вибірки()
    слова = {}
    for л in gzip.open(КОРІНЬ / "каталог_записи_v1.jsonl.gz", "rt", encoding="utf-8"):
        р = json.loads(л)
        if р.get("ід") in записи:
            слова[р["ід"]] = {"назва": р.get("назва"), "опис": (р.get("опис") or "")[:1500],
                              "параметри": р.get("параметри")}
    фото = sorted(os.listdir("/tmp/запис300/модель")) if os.path.isdir("/tmp/запис300/модель") else []
    таблиця = []
    for ід, р in записи.items():
        if р["слот"] not in ("взуття", "верхній_шар"):
            continue
        відомі = {f"{з}|{в}": зн for з, вх in р["записи"].items() for в, зн in вх.items() if зн not in (НЕВІДОМО, None)}
        таблиця.append({"ід": ід, "слот": р["слот"], "слова_крамниці": слова.get(ід),
                        "фото": [f"/tmp/запис300/модель/{ф}" for ф in фото if ф.startswith(ід + "-")],
                        "відомі_значення": відомі})
    json.dump(таблиця, open(шлях, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("речей:", len(таблиця), "значень:", sum(len(т["відомі_значення"]) for т in таблиця))


if __name__ == "__main__":
    os.chdir(КОРІНЬ / "джерела")
    if len(sys.argv) > 2 and sys.argv[1] == "--очима-таблиця":
        очима_таблиця(sys.argv[2])
        sys.exit(0)
    б = мірило_б(записи_вибірки())
    print("(б) невідомо й хибні на входах взуття й тепла, вибірка 300")
    for р in б:
        print(json.dumps(р, ensure_ascii=False))
    print("(в) охайна й демісезон на 40 речах огляду 21.11")
    print(json.dumps(мірило_в(), ensure_ascii=False, indent=1))
    print("(г) токени на кандидата в запиті складання с5")
    print(json.dumps(мірило_г(), ensure_ascii=False, indent=1))
