def P(р, к):
    for п in р["параметри"]:
        if п[0] == к: return п[1]
def поля_крамниці(р):
    рядки = ["назва: " + р["назва"]]
    м = P(р, "категорія_магазину")
    if м: рядки.append("розділ крамниці: " + м)
    пари = []
    for п in р["параметри"]:
        к, з = п[0], str(п[1])
        if (к.startswith("~") and not any(з_ in к for з_ in ЗАЙВІ)) or к in ("Колір", "Склад", "Матеріал", "Сезон"):
            if з.strip(): пари.append("%s: %s" % (к.lstrip("~"), з[:100]))
    рядки += пари[:20]
    о = (р.get("опис") or "").strip()
    if о: рядки.append("опис: " + о[:700])
    return "\n".join(рядки)
