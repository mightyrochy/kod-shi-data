#!/usr/bin/env python3
"""Точність кожного джерела по полях з позначок людини на сторінці `ohliad-zapysu/`.
Запуск з кореня: python3 .../точність.py <відповіді.json>  (JSON зі кнопки «Скопіювати всі відповіді»: {"<ід>|<поле>": "<літера>|жодне|не видно"}).
Джерело влучило, коли людина обрала літеру, під якою воно стоїть (дані/ключ_карток.json); «жодне» і «не видно» — нікому. Друкує таблицю поле × джерело."""
import collections, json, sys
К = json.load(open("аудит/проби/запис-речі-вибірка-300/дані/ключ_карток.json", encoding="utf-8"))
В = json.load(open(sys.argv[1], encoding="utf-8"))
вл = collections.defaultdict(collections.Counter); всього = collections.Counter(); без = collections.Counter()
for кл, в in В.items():
    if кл not in К: continue
    п = кл.split("|")[1]
    if в not in К[кл]: без[(п, в)] += 1; continue
    всього[п] += 1
    for дж, літера in ((дж, л) for л, джерела in К[кл].items() for дж in джерела): вл[п][дж] += (літера == в)
    for літера, джерела in К[кл].items():
        for дж in джерела: вл[п]["усього:" + дж] += 1
print("| поле | карток з вибраним варіантом | словник влучив | Sonnet влучив | Haiku влучив | «жодне» | «не видно» |\n|---|---|---|---|---|---|---|")
for п in sorted(всього | collections.Counter({п: 0 for п, _ in без})):
    ч = lambda дж: "%d з %d" % (вл[п][дж], вл[п]["усього:" + дж])
    print("| %s | %d | %s | %s | %s | %d | %d |" % (п, всього[п], ч("словник"), ч("Sonnet"), ч("Haiku"), без[(п, "жодне")], без[(п, "не видно")]))
