#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Проба приладу кореня ПК-дотримання-правил: подія лічиться правилу рядка лише за збігом ролі й рушія сесії.

Звірка зі збереженим виводом #2426 (`аудит/корені/ПК-дотримання-правил-вивід.txt`): підсумки «правило · роль · рушій · дій ·
порушень» з нього подаються в `за_рядком`, і кожен рядок розділу «за правилами переліку» порівнюється з тим, що було:
рядки з рушієм `Claude` чи `усі` мають збігтися точно, рядки лише Codex чи `agy` — давати 0/0. Запуск з кореня репозиторію:
  python3 -I аудит/проби/пк_атрибуція_рушія.py
Код завершення 0 — лише очікувані розбіжності.
"""
import os
import re
import runpy
import subprocess
import sys
import tempfile

КОРІНЬ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
ПЕРЕЛІК = os.path.join(КОРІНЬ, "аудит/корені/ПК-дотримання-правил-перелік.md")
ВИВІД = os.path.join(КОРІНЬ, "аудит/корені/ПК-дотримання-правил-вивід.txt")
# Вивід збережено з адресами номерами рядків переліку коміту 2f7bcbdc; рядок переліку тепер — адреса-цитата
# (наряд ПК-перелік-адреси): адресу виводу переводить правило (стовпець «правило») переліку того коміту.
КОМІТ_ВИВОДУ = "2f7bcbdc"


def правило_за_старою_адресою(п):
    """Стара адреса · слід → правило · слід за переліком коміту виводу."""
    текст = subprocess.run(["git", "-C", КОРІНЬ, "show", f"{КОМІТ_ВИВОДУ}:аудит/корені/ПК-дотримання-правил-перелік.md"],
                           capture_output=True, check=True, text=True, encoding="utf-8").stdout
    with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False, encoding="utf-8") as ф:
        ф.write(текст)
    try:
        return {к[0] + " · " + к[6]: к[1] + " · " + к[6] for к in п["таблиці_переліку"](ф.name)[0]}
    finally:
        os.unlink(ф.name)


def головна():
    п = runpy.run_path(os.path.join(КОРІНЬ, "джерела/прилади/корінь_пк_дотримання.py"))
    підсумок, старе, розділ = {}, {}, ""
    за_правилом = правило_за_старою_адресою(п)
    for рядок in open(ВИВІД, encoding="utf-8"):
        рядок = рядок.rstrip("\n")
        if рядок.startswith("-- "):
            розділ = рядок
        ч = рядок.split(" · ")
        if розділ.startswith("-- правило") and len(ч) >= 6 and re.fullmatch(r"К\d+", ч[0]):
            підсумок[(ч[0], ч[2], ч[3])] = (int(ч[4]), int(ч[5]))
        elif розділ.startswith("-- за правилами") and len(ч) >= 4 and ч[2].startswith("ролі"):
            старе[за_правилом.get(ч[0] + " · " + ч[1], ч[0] + " · " + ч[1])] = ч[3]
    нове, розбіжності, нулі = 0, [], 0
    for к in п["таблиці_переліку"](ПЕРЕЛІК)[0]:
        ключ = к[1] + " · " + к[6]
        if ключ not in старе:
            continue
        нове += 1
        рядок = п["за_рядком"](к, підсумок)
        claude = "усі" in п["рушії_рядка"](к) or "Claude" in п["рушії_рядка"](к)
        if claude and рядок != старе[ключ]:
            розбіжності.append((к[0], "рядок Claude/усі змінився", старе[ключ], рядок))
        if not claude:
            нулі += 1
            if not all(x.endswith(" 0/0") or x.endswith("0/0") for x in рядок.split("; ")):
                розбіжності.append((к[0], "рядок лише Codex/agy не 0/0", старе[ключ], рядок))
    print(f"рядків переліку з кодом: {нове}; лише Codex/agy: {нулі}; розбіжностей: {len(розбіжності)}")
    for р in розбіжності:
        print("розбіжність:", *р)
    # Атрибуція за рядком: К11 (дії Claude) не лічиться рядку «усі · Codex».
    правило_к11 = за_правилом["CHATGPT.md:16–17 · К11"]
    к11 = next(к for к in п["таблиці_переліку"](ПЕРЕЛІК)[0] if к[1] + " · " + к[6] == правило_к11)
    print("CHATGPT.md:16–17 (усі · Codex), було:", старе.get(правило_к11), "стало:", п["за_рядком"](к11, підсумок))
    return 1 if розбіжності else 0


if __name__ == "__main__":
    sys.exit(головна())
