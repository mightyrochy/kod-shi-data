def зняти(вхід):
    """Повертає екран і пакет саме його виклику, не перебудовуючи специфікацію."""
    пакети = []
    оригінал = МО.пакет
    def записати(*арг, **іменовані):
        """Запам'ятовує результат справжнього пакета без підміни даних."""
        пакет = оригінал(*арг, **іменовані)
        пакети.append(пакет)
        return пакет
    МО.пакет = записати
    try:
        екран = json.loads(М.палітри(вхід))
    finally:
        МО.пакет = оригінал
    пакет = пакети[-1]
    гілки = пакет["палітри"]["розвилка"]
    return dict(вхід=вхід, екран=екран,
                поєднання=[г["спец"]["палітра_практична"]["поєднання"] for г in гілки],
                бриф=[П.для_пакета(г["спец"]["палітра_практична"]) for г in гілки],
                базові=[(г["спец"].get("мисматч") or {}).get("базова", г["схема"]) for г in гілки])


def повтор(кольори):
    """Лічить повтор сім'ї тією самою функцією, що й K-COMP-03/K-PAL-07."""
    записи = []
    for колір in кольори:
        lab = КС.hx(колір)
        L, C, h = КС.lch(lab)
        if not К._нейтральний_тон(h, C, L):
            записи.append(dict(lab=lab))
    return any(КР.та_сама_сім_я(а, б) == "так" for а, б in itertools.combinations(записи, 2))


def підсумок(персони):
    """Звіряє кожний чип з першим поєднанням його прийому у справжньому пакеті."""
    збіги = повтори = трійки = порожні = 0
    for персона in персони:
        збіг = True
        for г, поєднання, базова in zip(персона["екран"]["гілки"], персона["поєднання"], персона["базові"]):
            прийом = {"нейтрали+акцент": "нейтраль_плюс_акцент", "тональна": "тон_у_тон"}.get(базова, базова)
            обране = next((п for п in поєднання if п["прийом"] == прийом), {})
            очікувані = [к["hex"] for к in обране.get("кольори", [])]
            кольори = г.get("зразки", [])
            збіг &= кольори == очікувані
            порожні += not кольори
            if г["схема"] == "аналогова" and len(кольори) == 3:
                трійки += 1
                повтори += повтор(кольори)
        збіги += збіг
    return dict(персон=len(персони), збіглися=збіги, аналогових_трійок=трійки,
                повторів=повтори, порожніх_чипів=порожні)


