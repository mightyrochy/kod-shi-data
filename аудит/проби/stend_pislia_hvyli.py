# -*- coding: utf-8 -*-
"""Підсумок 12 сідів `рв6_стенд.js` без ручного читання логу (сесія-вимір після
хвилі 19.09: #145 повтор рук, #146 R-COL-16, #147 наміри/K-IO-01, #150 Pointer,
#151 розмір/крій, #153 K-COND-04). Рахує РІВНО ТІ числа, які досі читали з логу
очима: ✔/✗, повтор речі між руками 1-2, скільки сідів дали знахідку K-SIZ-02 чи
R-FP-07 у топ-5 «код не знає», сім'ї чипів палітри і час прогону. Не звірка —
жоден рядок не падає, лише друк факту.

Запуск: python3 аудит/проби/stend_pislia_hvyli.py /tmp/rv6_logs/seed*.log"""
import sys, glob, re

файли = sorted({ш for г in sys.argv[1:] for ш in glob.glob(г)})
assert файли, "дай шлях(и) до логів рв6_стенд.js, напр. /tmp/rv6_logs/seed*.log"
ок = впало = повтор = сиз = фп = кол16 = 0
часи, рука1_часи, сімї_бачені = [], [], set()
for ш in файли:
    т = open(ш, encoding="utf-8").read()
    ок += len(re.findall(r"(?m)^  ✔", т))
    впало += len(re.findall(r"(?m)^  ✗", т))
    повтор += 1 if "повтор речі з руки" in т else 0
    сиз += 1 if "розмір — це номер, не посадка" in т else 0
    фп += 1 if re.search(r"крій (прочитано з фото|узято зі слова крамниці)", т) else 0
    кол16 += 1 if "R-COL-16" in т else 0
    час = re.search(r"·\s*([\d.]+)\s*с\s*$", т.strip())
    if час:
        часи.append(float(час.group(1)))
    if (р1 := re.search(r"рука 1: картка за ([\d.]+) с", т)): рука1_часи.append(float(р1.group(1)))
    сім = re.search(r"сім'ї по порядку:\s*(\[[^\]]*\])", т)
    if сім:
        сімї_бачені.add(сім.group(1))

print("сідів %d · ✔ %d · ✗ %d" % (len(файли), ок, впало))
print("повтор речі між руками 1–2: %d/%d сідів" % (повтор, len(файли)))
print("K-SIZ-02 «розмір — це номер»: %d/%d · R-FP-07 «крій …»: %d/%d · R-COL-16: %d/%d"
      % (сиз, len(файли), фп, len(файли), кол16, len(файли)))
if часи:
    print("час прогону: мін %.1f с · медіана %.1f с · макс %.1f с"
          % (min(часи), sorted(часи)[len(часи) // 2], max(часи)))
if рука1_часи: print("рука 1: мін %.1f с · медіана %.1f с · макс %.1f с (межа +20%% із #126)" % (min(рука1_часи), sorted(рука1_часи)[len(рука1_часи) // 2], max(рука1_часи)))
print("сім'ї чипів палітри (унікальні порядки на всіх сідах): %s" % sorted(сімї_бачені))
