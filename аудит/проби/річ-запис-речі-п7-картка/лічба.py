# -*- coding: utf-8 -*-
"""Річ-запис-речі п.7, крок 2 (наряд «Річ-запис-речі-п7-картка-в-запис»): що картка крамниці каже про пару — вид і клас
каблука, висота, підошва, сезон, підкладка — і що з цього стоїть у рядку стилістки. Повний каталог продукту
(`каталог_повний.xml.gz`), усі 3 399 пар взуття, не вибірка.

«Картка каже» — таблиця читань мовної моделі `джерела/картка_взуття.py` (пара «поле → значення» → коди) і, для висоти,
ще число чи смуга, які вже читає `фід_взуття` (`висота_з_параметрів`, `смуга_каблука`). «Рядок» — вихід того самого
шляху, що будує пул у `пакет_моделі` (`graph.зона` → `дріт_моделі.осі` з тими самими входами, як `лічба.py` кроку 1).
Таблицю завжди беремо з цієї гілки (шлях `--таблиця`), продукт — з `--джерела`: так ДО (код `main`) і ПІСЛЯ міряють
одним мірилом. Моделей не кличе.

Запуск: python3 аудит/проби/річ-запис-речі-п7-картка/лічба.py --джерела <тека джерела> --кеш <файл.pkl> --вихід <файл.json>
"""
import argparse, collections, gzip, html, importlib.util, json, os, pickle, re, sys, warnings

ТУТ = os.path.dirname(os.path.abspath(__file__))
КОРІНЬ = os.path.dirname(os.path.dirname(os.path.dirname(ТУТ)))
а = argparse.ArgumentParser()
а.add_argument("--джерела", default=os.path.join(КОРІНЬ, "джерела"))
а.add_argument("--таблиця", default=os.path.join(КОРІНЬ, "джерела", "картка_взуття.py"))
а.add_argument("--кеш")
а.add_argument("--вихід", default=os.path.join(ТУТ, "числа.json"))
АРГ = а.parse_args()
АРГ.вихід, АРГ.таблиця = os.path.abspath(АРГ.вихід), os.path.abspath(АРГ.таблиця)
warnings.simplefilter("ignore")
сп = importlib.util.spec_from_file_location("таблиця_картки", АРГ.таблиця)
К = importlib.util.module_from_spec(сп); сп.loader.exec_module(К)
sys.path.insert(0, АРГ.джерела); os.chdir(АРГ.джерела)
import фід_каталог as ФК, дріт_моделі as Д, graph as ГР, каблук as КБ, фід_взуття as ФВ  # noqa: E402

if АРГ.кеш and os.path.exists(АРГ.кеш):
    каталог = pickle.load(open(АРГ.кеш, "rb"))
else:
    каталог = ФК.прочитати_каталог(ФК.каталог_на_диску(), ліміт_фото=0)["каталог"]
    if АРГ.кеш:
        pickle.dump(каталог, open(АРГ.кеш, "wb"))
взуття = [r for r in каталог if r.get("слот") == "взуття"]

xml = gzip.open(os.path.join(КОРІНЬ, "каталог_повний.xml.gz"), "rt", encoding="utf-8").read()
картки = {}
for м in re.finditer(r'<offer id="([^"]+)"[^>]*>(.*?)</offer>', xml, re.S):
    if '<param name="слот">взуття</param>' in м.group(2):
        # імена — малими літерами й значення без сутностей XML, як їх кладе в `параметри` розбір фіду (`фід_розбір`)
        картки[м.group(1)] = {html.unescape(a).strip().lower(): html.unescape(b)
                              for a, b in re.findall(r'<param name="([^"]*)">(.*?)</param>', м.group(2), re.S)}

НЕМА = (None, "unknown", "not_read")


def є(v):
    return v not in НЕМА and v != []


def висота_картки(пар):
    """Чи картка називає висоту каблука >0 числом чи смугою: таблиця читань або те, що вже читає `фід_взуття`."""
    к = К.ознаки(пар).get("висота_картки")
    if к and (к.get("см") or 0) > 0 or (к and "від" in к):
        return True
    for ім, зн in пар.items():
        if К.група(ім) != "висота":
            continue
        h = ФВ.висота_з_параметрів({ім: зн})
        if (h and h[0] > 0) or ФВ.смуга_каблука(зн):
            return True
    return False


ч, зразки, рядки = collections.Counter(), collections.defaultdict(list), {}
поля_значення = collections.defaultdict(collections.Counter)
for r in взуття:
    ід = r["id"].split("@")[0]
    пар = картки.get(ід) or {}
    кб = КБ.каблук(r["назва"], None, r.get("url"))
    рч = dict(r, слот="взуття")
    о = Д.осі(ГР.зона(рч), dict(рч, каблук_є=кб["є"], каблук=r.get("каблук"), каблук_форма=кб["форма"],
                              каблук_висота=кб["висота"], каблук_словами=КБ.словами(кб)))
    к = К.ознаки(пар)
    for ім, зн in пар.items():
        if К.група(ім):
            поля_значення[ім][" ".join(зн.split())] += 1
    ч["пар"] += 1
    ч["картка знайдена в XML"] += bool(пар)
    # ── що в рядку ──
    ч["рядок: вид каблука (heel_shape)"] += є(о.get("heel_shape"))
    ч["рядок: клас висоти (heel_height)"] += є(о.get("heel_height"))
    ч["рядок: висота числом чи смугою (heel_cm)"] += є(о.get("heel_cm"))
    ч["рядок: підошва не unknown (sole)"] += є(о.get("sole"))
    ч["рядок: сезон пари (wear_season)"] += є(о.get("wear_season"))
    ч["рядок: підкладка (lining)"] += є(о.get("lining"))
    ч["рядок: heel=" + str(о.get("heel"))] += 1
    for ключ in ("heel_shape", "heel_cm", "sole", "wear_season", "lining"):
        ч["рядок: %s=not_read" % ключ] += о.get(ключ) == "not_read"
    # ── картка назвала, а рядок «невідомо» (за полями картки) ──
    втрати = dict(
        вид=bool(к.get("каблук_вид")) and not є(о.get("heel_shape")),
        клас=bool(к.get("каблук_рівень")) and not є(о.get("heel_height")),
        висота=висота_картки(пар) and not є(о.get("heel_cm")),
        каблук_є=("каблук" in к) and о.get("heel") in НЕМА,
        підошва=bool(к.get("підошва_коди")) and not є(о.get("sole")),
        сезон=bool(к.get("сезон_пари")) and not є(о.get("wear_season")),
        підкладка=bool(к.get("підкладка_коди")) and not є(о.get("lining")),
    )
    for ім, v in втрати.items():
        ч["картка назвала: %s" % ім] += bool({"вид": к.get("каблук_вид"), "клас": к.get("каблук_рівень"),
                                              "висота": висота_картки(пар), "каблук_є": "каблук" in к,
                                              "підошва": к.get("підошва_коди"), "сезон": к.get("сезон_пари"),
                                              "підкладка": к.get("підкладка_коди")}[ім])
        ч["ВТРАТА картка назвала, рядок «невідомо»: %s" % ім] += v
        if v and len(зразки[ім]) < 5:
            зразки[ім].append(dict(id=r["id"], назва=r["назва"], картка={п: з for п, з in пар.items() if К.група(п)},
                                   рядок={x: о.get(x) for x in ("heel", "heel_shape", "heel_height", "heel_cm", "sole",
                                                                 "wear_season", "lining")}))
    # суперечність: картка каже «каблука нема», а рядок «yes» (чи навпаки)
    if "каблук" in к:
        с = (к["каблук"] and о.get("heel") == "none") or (not к["каблук"] and о.get("heel") == "yes")
        ч["суперечність картка/рядок heel"] += с
        if с and len(зразки["суперечність heel"]) < 12:
            зразки["суперечність heel"].append(dict(
                id=r["id"], назва=r["назва"], картка={п: з for п, з in пар.items() if К.група(п)},
                запис={x: r.get(x) for x in ("каблук", "каблук_см", "каблук_від", "каблук_до", "каблук_клас")},
                рядок={x: о.get(x) for x in ("heel", "heel_shape", "heel_height", "heel_cm")}))
    if ід in ("ж-09146", "ж-10131"):
        рядки[ід] = dict(назва=r["назва"], рядок=о, картка={п: з for п, з in пар.items() if К.група(п)})

# ── різні значення полів: скільки, прочитано з кодом, прочитано «невідомо» (порожньо), не прочитано ──
покриття = {}
for ім, зн in sorted(поля_значення.items(), key=lambda x: -sum(x[1].values())):
    група = К.група(ім)
    кодом = [v for v in зн if К.прочитати(ім, v)]
    порожньо = [v for v in зн if К.прочитати(ім, v) == {}]
    поза = [v for v in зн if К.прочитати(ім, v) is None]
    if група == "висота":     # числом чи смугою їх читає `фід_взуття`, не таблиця
        поза = [v for v in поза if not (ФВ.висота_з_параметрів({ім: v}) or ФВ.смуга_каблука(v))]
    if група == К.СКЛАД:      # поле складу каже про підошву й підкладку лише деякими значеннями
        поза = []
    покриття[ім] = dict(група=група, пар=sum(зн.values()), різних=len(зн), прочитано_кодом=len(кодом),
                        прочитано_невідомо=len(порожньо), не_прочитано=len(поза), приклади_не_прочитано=поза[:5])
таблиця = {г: len(т) for г, т in К.ЧИТАННЯ.items()}
вихід = dict(числа=dict(ч), покриття_полів=покриття, значень_у_таблиці=таблиця,
             значень_у_таблиці_разом=sum(таблиця.values()),
             значень_невідомо=sum(1 for т in К.ЧИТАННЯ.values() for v in т.values() if not v),
             рядки=рядки, зразки_втрат=dict(зразки))
json.dump(вихід, open(АРГ.вихід, "w", encoding="utf-8"), ensure_ascii=False, indent=1, default=str)
for к_, v in ч.items():
    print("%-70s %s" % (к_, v))
print("таблиця:", таблиця, "разом", вихід["значень_у_таблиці_разом"], "порожніх", вихід["значень_невідомо"])
print("не прочитано (поле: число різних):", {ім: п["не_прочитано"] for ім, п in покриття.items() if п["не_прочитано"]})
for ід, р in рядки.items():
    print(ід, json.dumps(р, ensure_ascii=False, default=str))
