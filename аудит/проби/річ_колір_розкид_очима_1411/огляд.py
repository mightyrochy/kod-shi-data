"""З'єднати ручні вердикти з усіма кадрами й збереженим контекстом виміру.

З кореня: python -X utf8 -I аудит/проби/річ_колір_розкид_очима_1411/огляд.py
Вердиктів не обчислює; їх джерело — оцінки.tsv, заповнений після огляду фото.
"""
import csv
import gzip
import json
import subprocess
from collections import Counter
from pathlib import Path

ТУТ = Path(__file__).resolve().parent
ДЖЕРЕЛО = "c7b37862c5195f823e0ef211cd8ecd718b498f95"


def читати(назва):
    with (ТУТ / назва).open(encoding="utf-8", newline="") as ф:
        return list(csv.DictReader(ф, delimiter="\t"))


def записати(назва, рядки):
    with (ТУТ / назва).open("w", encoding="utf-8", newline="") as ф:
        п = csv.DictWriter(ф, fieldnames=list(рядки[0]), delimiter="\t", lineterminator="\n")
        п.writeheader()
        п.writerows(рядки)


def обʼєкт(шлях):
    return subprocess.check_output(["git", "show", f"{ДЖЕРЕЛО}:{шлях}"])


def головна():
    кадри = читати("вибірка.tsv")
    оцінки = читати("оцінки.tsv")
    за_номером = {р["номер"]: р for р in оцінки}
    assert len(оцінки) == len(за_номером) == 40
    ід = {р["id"].split("@")[0] for р in кадри}
    каталог = {}
    for рядок in gzip.decompress(обʼєкт("каталог_записи_v1.jsonl.gz")).decode("utf-8").splitlines():
        р = json.loads(рядок)
        if р.get("ід") in ід:
            каталог[р["ід"]] = р
    виміри = json.loads(gzip.decompress(обʼєкт("аудит/проби/річ_колір_розкид_0811/перевимір.json.gz")))["записи"]
    контекст, огляд = [], []
    for р in кадри:
        о = за_номером[р["номер"]]
        запис = каталог[р["id"].split("@")[0]]
        в = next(в for в in виміри[р["id"]] if в["файл"] == р["файл"])
        assert в["hex"] == р["hex"] and в["слово"] == р["код"]
        контекст.append(dict(номер=р["номер"], кадр=р["кадр"], id=р["id"], назва=запис["назва"],
                             адреса=запис["адреса"], файл=р["файл"], клас=в.get("клас"),
                             маска=в.get("маска"), частка_маски=в.get("частка_маски"),
                             lab=json.dumps(в.get("lab")), чому=в.get("чому"),
                             поверхня=в["вимір"]["чому"],
                             кластери=json.dumps(в.get("кластери"), ensure_ascii=False)))
        кадр_вердикт = о["вердикт"]
        видно, уточнення = о["що_видно"], о["уточнення"]
        if р["номер"] == "36":
            видно = {"1": "Оливково-коричневий короткий тренч, кадр збоку; коричнева латка близька, слово оливковий/коричневий межове.",
                     "2": "Той самий короткий тренч, загальний кадр; коричнева латка близька, тон оливковий/коричневий межовий.",
                     "3": "Чорний спортивний верх і штани, короткого тренча немає.",
                     "4": "Чорний укорочений светр і сірі штани, короткого тренча немає."}[р["кадр"]]
            кадр_вердикт = "межова" if р["кадр"] in ("1", "2") else "хибна"
        if р["номер"] == "37" and р["кадр"] == "4":
            видно = "Деталь дуже темного коричневого пальта; у затіненій частині чорний/шоколад межовий, інші три кадри коричневі."
            кадр_вердикт = "межова"
        номер_кадру = кадри.index(р)
        огляд.append(dict(номер=р["номер"], id=р["id"], ціль=запис["назва"], кадр=р["кадр"],
                          файл=р["файл"], фото=р["фото"], hex=р["hex"], код=р["код"],
                          що_видно=видно, вердикт_кадру=кадр_вердикт, вердикт_речі=о["вердикт"],
                          причина=о["причина"], уточнення=уточнення,
                          аркуш=f"аркуш-{номер_кадру // 8 + 1:02d}.jpg"))
    записати("контекст.tsv", контекст)
    записати("огляд.tsv", огляд)
    print("Речі:", dict(Counter(о["вердикт"] for о in оцінки)))
    print("Хибні за головною причиною:", dict(Counter(о["причина"] for о in оцінки if о["вердикт"] == "хибна")))
    print("Кадрів оглянуто:", len(огляд))


if __name__ == "__main__":
    головна()
