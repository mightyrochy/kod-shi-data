/* Запис входів мосту одного прогону стенда (крок 0.2-А, рядки 8260–8264 дошки).
   Знімок швидкодії й поведінки мусить міряти те, що біжить у Pyodide, на тих самих входах, а не вигадані:
   стенд з `ZAPYS_VYKLYKIV=<файл.jsonl>` пише кожен виклик `містП` (єдиний вхід показу в `bridge`) рядком JSON.
   Відтворює їх `джерела/прилади/знімок_мосту.py`. Без змінної — нічого не міняється.
   Запис іде з боку Node через `exposeFunction` одразу на диск: стенд має десяток `process.exit`, і
   збирати журнал у пам'яті сторінки до кінця прогону не можна. */
const fs = require('fs');

const ФАЙЛ = process.env.ZAPYS_VYKLYKIV || null;
const УВІМКНЕНО = !!ФАЙЛ;

/* `поступливий` — те саме правило, що в `показ.html: містП`: «суд» і «каталог» оцінки йдуть `bridge.виклик_а` */
async function встановити(стор){
  if (!УВІМКНЕНО) return;
  fs.writeFileSync(ФАЙЛ, '');
  await стор.exposeFunction('__записВиклику', рядок => { fs.appendFileSync(ФАЙЛ, рядок + '\n'); });
  await стор.evaluate(() => {
    const о = window.містП;
    window.містП = function(ім, дані){
      const асинх = ім === 'оцінка' && !!дані && (дані.крок === 'суд' || дані.крок === 'каталог');
      window.__записВиклику(JSON.stringify({ім, 'async': асинх, 'вхід': JSON.stringify(дані === undefined ? null : дані), w0: Date.now()}));
      return о.apply(this, arguments);
    };
  });
  console.log('запис входів мосту →', ФАЙЛ);
}

module.exports = {УВІМКНЕНО, встановити};
