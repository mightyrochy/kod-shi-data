"""Виміряти читачів типу/слота на всьому фіді та зафіксувати вибірку сторінок.

Запуск із кореня: python -X utf8 аудит/проби/річ_запис_каталог.py --вихід ТЕКА
Без `--вихід` — тимчасова тека поза деревом: голий прогін (`лічба_проб.py`)
переписував записаний доказ `аудит/проби/річ_запис_каталог_2026_10_30` (Д11,
`аудит/корені/Приховані-перелік-д.md`); запис доказу — лише явним `--вихід`.
Не змінює продукт, каталог, кеші жнив. HTTP виконується лише з --сторінки;
повтор виміру використовує зафіксовані відповіді, а не поточні сайти.
"""
import argparse
import collections
import concurrent.futures
import gzip
import hashlib
import inspect
import itertools
import json
import os
from pathlib import Path
import random
import re
import ssl
import subprocess
import sys
import tempfile

КОРІНЬ = Path(__file__).resolve().parents[2]
ЗЕРНО = 11658
sys.path[:0] = [str(КОРІНЬ / 'джерела'), str(КОРІНЬ / 'zhnyvarka')]


def записати(шлях, дані):
    """Записати JSON із фіксованим порядком ключів і завершальним переносом."""
    шлях.write_text(json.dumps(дані, ensure_ascii=False, sort_keys=True, indent=2) + '\n', encoding='utf-8')


def стиснути(шлях, дані):
    """Зберегти байти без часу й імені файла в заголовку gzip."""
    шлях.write_bytes(gzip.compress(дані, mtime=0))


def відбиток(шлях):
    """Порахувати SHA256 файла джерела."""
    return hashlib.sha256(шлях.read_bytes()).hexdigest()


def адреса_функції(функція):
    """Показати справжнє місце викликаної функції в зафіксованому дереві."""
    return str(Path(inspect.getsourcefile(функція)).relative_to(КОРІНЬ)).replace('\\', '/') + ':' + str(inspect.getsourcelines(функція)[1])


def офери(імя):
    """Розпакувати тільки в TEMP і прочитати штатним читачем продукту."""
    from фід_розбір import читати_yml
    with tempfile.TemporaryDirectory(prefix='rich-', dir=os.environ.get('TEMP') or None) as т:
        шлях = Path(т) / 'catalog.xml'
        шлях.write_bytes(gzip.decompress((КОРІНЬ / імя).read_bytes()))
        return читати_yml(str(шлях))[0]


def причина_без_типу(офер):
    """Зберегти входи та результати реальних проходів словника для кожного None."""
    import фід_слот as читач
    назва = читач.назва_суду(офер)
    категорія = офер.get('категорія') or ''
    повна_назва = читач.предмет_типу(читач.re_тип.sub(' ', назва.lower()))
    розділ = читач.предмет_типу(читач.re_тип.sub(' ', категорія.lower()))
    голова = читач.re_тип.sub(' ', назва.lower())
    if (офер['параметри'].get('назва_джерело') or '').strip().lower() == 'опис':
        голова = ' '.join(голова.split()[:читач.СТЕЛЯ_СЛІВ_ГОЛОВИ + 2])
        голова = re.split(r'\b(?:і|й|та|або)\b', голова, maxsplit=1)[0]
    if not назва.strip():
        причина = 'порожня назва'
    elif повна_назва and not читач.предмет_типу(голова):
        причина = 'іменник поза межею голови назви з опису'
    elif розділ and читач.деталь_у_назві(голова) and розділ[0] in читач._ТИПИ_ДЕТАЛІ:
        причина = 'розділ називає деталь; категорію виключено через прийменник у назві'
    elif повна_назва and повна_назва[0] == 'комплект' and читач._набір_зі_слів(офер) is not True:
        причина = 'слово набір без підтвердження різних слотів; комплект виключено'
    elif повна_назва or розділ:
        причина = 'інше: слово знайдено; обмеження контексту/набору в _вид_зі_слів'
    elif читач.предмет_типу(читач.re_тип.sub(' ', str(офер.get('назва') or '').lower())):
        причина = 'інше: сира назва і назва суду різні'
    else:
        причина = 'нема прийнятого іменника у словнику назви й розділу'
    return dict(причина=причина, назва=назва, назва_сира=офер.get('назва'),
                категорія=категорія, оголошений_тип=офер['параметри'].get('тип'),
                джерело_назви=офер['параметри'].get('назва_джерело'),
                предмет_назви=повна_назва, предмет_розділу=розділ,
                голова=голова, предмет_голови=читач.предмет_типу(голова))


def поля_вибірки(вибірка):
    """Брати поля для звірки зі сторінкою з v1, зокрема опис у власному XML-тезі.

    Читач типу навмисно бачить свій штатний офер. Перевірка походження поля
    мусить бачити сам запис каталогу: читач YML переносить лише param опис.
    """
    за_ключем = {(р['id'].split('@')[0], р['url']): р for р in вибірка}
    with gzip.open(КОРІНЬ / 'каталог_записи_v1.jsonl.gz', 'rt', encoding='utf-8') as ф:
        for рядок in ф:
            р = json.loads(рядок)
            зразок = за_ключем.get((р.get('ід'), р.get('адреса')))
            if зразок is not None:
                зразок.update(назва=р.get('назва'), опис=р.get('опис'))
    return вибірка


def виміряти(вихід):
    """Викликати чинні читачі на кожному записі повного каталогу."""
    subprocess.run(['git', 'diff', '--exit-code', 'HEAD',
        '--', 'джерела', 'zhnyvarka', 'каталог_повний.xml.gz', 'каталог_записи_v1.jsonl.gz'],
        cwd=КОРІНЬ, check=True, stdout=subprocess.DEVNULL)
    import фід_слот as читач
    import фід_верхнє as верхнє
    from фід_розбір import побудувати_запис_речі
    from фід_збагачення import форма_запису, _слот_фото
    from жниварка import слот_речі
    import каталог_розбір as розбір
    речі = офери('каталог_повний.xml.gz')
    збагачення = json.loads(gzip.decompress((КОРІНЬ / 'джерела/каталог_збагачення.json.gz').read_bytes()))
    записи, без_типу, приклади = [], [], []
    пари = collections.Counter()
    пари_крамниці = collections.defaultdict(collections.Counter)
    крамниці = collections.defaultdict(collections.Counter)
    покриття = collections.Counter()
    for о in sorted(речі, key=lambda о: о['id']):
        т, с, н, д = читач.вид_речі(о)
        запис = побудувати_запис_речі(о)
        з_записом = dict(о, запис_речі=запис)
        # Розбір сам приєднує запис перед читанням, як на живому шляху.
        коди, збої = розбір.що_каже_код(з_записом)
        if збої:
            raise RuntimeError((о['id'], збої))
        import внутрішня_мова as мова
        тип_коду = мова.ТАБЛИЦЯ['item_type'].get(коди.get('item_type'))
        слот_коду = мова.ТАБЛИЦЯ['slot'].get(коди.get('slot'))
        крихти = re.split(r'\s*(?:>| / )\s*', о['параметри'].get('категорія_магазину') or '')
        сл_жнив, дж_жнив = слот_речі(крихти, о['назва'], о['url'])
        атрибути = верхнє.верхні_атрибути(з_записом)
        читачі = {
            'вид_офера': dict(тип=т, слот=с),
            'фід_суд': dict(тип=читач.тип_речі(о, читач.слот(о)), слот=читач.слот(о)),
            'запис_входу': dict(тип=запис['тип'], слот=запис['слот']),
            'читання_запису': dict(тип=читач.тип_речі(з_записом), слот=читач.слот(з_записом)),
            'верхні_атрибути': ({'тип': атрибути['тип_верхнього']} if 'тип_верхнього' in атрибути else {}),
            'розбір_коду': dict(тип=тип_коду, слот=слот_коду),
            'жниварка_повтор': dict(слот=сл_жнив),
        }
        форма = форма_запису(збагачення.get(о['id']) or {})
        if форма and форма.get('опис'):
            читачі['кадр'] = dict(слот=_слот_фото(форма['опис'], запис['слот']))
        різні = []
        for (а, ва), (б, вб) in itertools.combinations(sorted(читачі.items()), 2):
            for поле in sorted(ва.keys() & вб.keys()):
                ключ = f'{а} / {б} / {поле}'
                покриття[ключ] += 1
                if ва[поле] != вб[поле]:
                    пари[ключ] += 1
                    пари_крамниці[о['магазин']][ключ] += 1
                    різні.append(ключ)
        ряд = dict(id=о['id'], крамниця=о['магазин'], url=о['url'], назва=о['назва'],
                   назва_суду=читач.назва_суду(о), кадр=(о['фото'] or [None])[0],
                   категорія=о['категорія'], категорія_магазину=о['параметри'].get('категорія_магазину'),
                   читачі=читачі, різні=різні, джерело_типу=д,
                   джерело_жнив=дж_жнив, опис_кадру=(форма or {}).get('опис'))
        записи.append(ряд)
        крамниці[о['магазин']]['речей'] += 1
        if різні:
            крамниці[о['магазин']]['розбіжні'] += 1
            приклади.append(ряд)
        if not запис['тип']:
            крамниці[о['магазин']]['без_типу'] += 1
            без_типу.append(dict(id=о['id'], крамниця=о['магазин'], url=о['url'], **причина_без_типу(о)))
    # Окрема оцінка: перерахунок стадії жнив і опис фото не дорівнюють читанню готового запису.
    готові = {'вид_офера', 'фід_суд', 'запис_входу', 'читання_запису', 'верхні_атрибути', 'розбір_коду'}
    розбіжні_готові = sum(any(а in готові and б in готові for а, б, п in (к.split(' / ') for к in р['різні'])) for р in записи)
    короткий = офери('джерела/каталог_brief.xml.gz')
    джерела = ['каталог_повний.xml.gz', 'каталог_записи_v1.jsonl.gz'] + [str(p.relative_to(КОРІНЬ)).replace('\\', '/') for p in sorted((КОРІНЬ / 'джерела').glob('каталог_*.gz'))]
    підсумок = dict(main_sha=subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=КОРІНЬ, text=True).strip(),
        джерела={п: відбиток(КОРІНЬ / п) for п in джерела}, зерно=ЗЕРНО,
        оферів=len(речі), короткий_фід=len(короткий), крамниць=len(крамниці),
        розбіжних=sum(bool(р['різні']) for р in записи), розбіжних_готових=розбіжні_готові,
        без_типу=len(без_типу), причини=dict(collections.Counter(р['причина'] for р in без_типу)),
        крамниці=крамниці, пари=пари, покриття_пар=покриття, пари_крамниці=пари_крамниці,
        функції={ф.__name__: адреса_функції(ф) for ф in [читач.вид_речі, читач.тип_речі, читач.слот,
            побудувати_запис_речі, верхнє.верхні_атрибути, розбір.що_каже_код, слот_речі, _слот_фото]})
    for імя, дані in [('читачі', записи), ('без_типу', без_типу)]:
        стиснути(вихід / (імя + '.jsonl.gz'), ''.join(json.dumps(р, ensure_ascii=False, sort_keys=True) + '\n' for р in дані).encode())
    записати(вихід / 'підсумок.json', підсумок)
    # Різні крамниці першими; потім різні пари читачів. Фіксований порядок.
    вибрані, бачені = [], set()
    for р in приклади:
        if р['крамниця'] not in бачені:
            вибрані.append(р); бачені.add(р['крамниця'])
    вибрані = (вибрані + [р for р in приклади if р not in вибрані])[:20]
    записати(вихід / 'приклади_20.json', вибрані)
    по_крамницях = collections.defaultdict(list)
    for о in речі:
        по_крамницях[о['магазин']].append(о)
    генератор = random.Random(ЗЕРНО)
    вибірка = []
    for крамниця, рядки in sorted(по_крамницях.items()):
        # Унікальні URL, інакше три розміри не становлять три сторінки.
        за_адресою = {о['url']: о for о in sorted(рядки, key=lambda о: о['id'])}
        кандидати = генератор.sample(sorted(за_адресою), min(3, len(за_адресою)))
        for url in кандидати:
            о = за_адресою[url]
            вибірка.append(dict(id=о['id'], крамниця=крамниця, url=url,
                назва=о['назва'], опис=о.get('опис'), склад=о['параметри'].get('склад'),
                розділ=о['параметри'].get('категорія_магазину') or о['категорія']))
    записати(вихід / 'вибірка.json', поля_вибірки(вибірка))
    print(json.dumps({к: підсумок[к] for к in ['оферів', 'крамниць', 'короткий_фід', 'розбіжних', 'розбіжних_готових', 'без_типу', 'причини']}, ensure_ascii=False))


def сертифікати():
    """Використати системні довірені CA Windows без вимикання TLS-перевірки."""
    import requests
    if not hasattr(ssl, 'enum_certificates'):
        return requests.certs.where()
    шлях = Path(os.environ['TEMP']) / 'rich-ca.pem'
    шлях.write_text(''.join(ssl.DER_cert_to_PEM_cert(c) for сховище in ['ROOT', 'CA']
                           for c, кодування, довіра in ssl.enum_certificates(сховище)
                           if кодування == 'x509_asn'), encoding='ascii')
    return str(шлях)


def сторінки(вихід):
    """Одноразово зберегти відповіді вибірки з URL, HTTP-станом і SHA256."""
    import requests
    вибірка = json.loads((вихід / 'вибірка.json').read_text(encoding='utf-8'))
    сховище = вихід / 'html'
    сховище.mkdir(exist_ok=True)
    довіра = сертифікати()

    def отримати(р):
        """Отримати одну публічну сторінку, зберігши також невдалий HTTP-стан."""
        імя = hashlib.sha256(р['url'].encode()).hexdigest()[:16] + '.html.gz'
        мета = dict(id=р['id'], url=р['url'], файл='html/' + імя)
        try:
            відповідь = requests.get(р['url'], timeout=25, verify=довіра)
            дані = відповідь.content
            стиснути(сховище / імя, дані)
            мета.update(стан=відповідь.status_code, кінцева=відповідь.url,
                        кодування=відповідь.encoding, sha256=hashlib.sha256(дані).hexdigest())
        except requests.RequestException as помилка:
            мета.update(помилка=type(помилка).__name__ + ': ' + str(помилка))
        return мета

    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as пул:
        результати = list(пул.map(отримати, вибірка))
    записати(вихід / 'сторінки.json', результати)
    print('Сторінки:', dict(collections.Counter(р.get('стан', 'збій') for р in результати)))


def main():
    """Запустити тільки явно вибрані етапи проби."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('--вихід', type=Path, default=None,
                        help='тека запису; без неї — тимчасова поза деревом (доказ — лише явно)')
    парсер.add_argument('--сторінки', action='store_true')
    парсер.add_argument('--лише-сторінки', action='store_true')
    а = парсер.parse_args()
    if а.вихід is None:
        import tempfile
        а.вихід = Path(tempfile.mkdtemp(prefix='річ_запис_каталог_'))
        print('вихід — тимчасова тека поза деревом:', а.вихід)
    а.вихід.mkdir(parents=True, exist_ok=True)
    if not а.лише_сторінки:
        виміряти(а.вихід)
    if а.сторінки or а.лише_сторінки:
        сторінки(а.вихід)


if __name__ == '__main__':
    main()
