"""Жорстке «ні» профілю й нейтраль речі на всьому каталозі — ДО і ПІСЛЯ одного визначення (спроба 12).

Запуск (модель і платні API не викликаються):
    python3 аудит/проби/Е3_жорстке_ні_слова.py <корінь дерева> <каталог.pickle.gz> [<рішення.json.gz>]
Каталог — список записів `feed._прочитати_каталог(feed.каталог_на_диску(), ліміт_фото=0)["каталог"]`,
збережений pickle-ом, щоб обидва дерева читали ті самі записи. Друкує лічбу й відбитки; третій аргумент
пише поіменні рішення для порівняння двох запусків.
  · жорстке «ні» (`profile.жорстке_ні_фільтр`) за кожним словом словника кольору — як у пробі спроби 11
    (`Е3_слова_кольору.py`), і вето пулу (`пакет_моделі.жорстке_відсічення`) тим самим словом: скільки пар
    (слово, річ) знімає лише одне з двох;
  · `колір_річ.нейтраль` на `lab` кожної речі й на сітці Lab (L* 0–100, a*, b* −60…60, крок 1).
"""
import gzip, hashlib, json, os, pickle, sys, warnings
from pathlib import Path


def головна():
    """Рішення жорсткого «ні», вето пулу й нейтралі для кожної речі каталогу."""
    дерево, каталог_шлях = Path(sys.argv[1]).resolve(), sys.argv[2]
    os.chdir(дерево / "джерела")
    sys.path.insert(0, str(Path.cwd()))
    warnings.simplefilter("ignore")
    import profile as П, пакет_моделі as М, колір_річ as КР, словник_кольору as СК
    with gzip.open(каталог_шлях, "rb") as ф:
        каталог = pickle.load(ф)
    слова = sorted(set(СК.НАЗВА_ПРОДУКТУ.values()))
    ні, пул = {}, {}
    for w in слова:
        _, відкинуті = П.жорстке_ні_фільтр(каталог, [w])
        ні[w] = sorted(str(в["id"]) for в in відкинуті)
        пул[w] = sorted(str(r.get("id")) for r in каталог
                        if (М.жорстке_відсічення(r, вето={"кольори": [w]}) or "").startswith("person_veto"))
    лише_пул = {w: sorted(set(пул[w]) - set(ні[w])) for w in слова}
    лише_ні = {w: sorted(set(ні[w]) - set(пул[w])) for w in слова}
    нейтраль = {str(r.get("id")): КР.нейтраль(r["lab"]) for r in каталог if r.get("lab")}
    сітка = [КР.нейтраль((L, a, b)) for L in range(0, 101) for a in range(-60, 61) for b in range(-60, 61)]
    def відбиток(о):
        return hashlib.sha256(json.dumps(о, ensure_ascii=False, sort_keys=True).encode()).hexdigest()[:16]
    нейтралей = {}
    for в in нейтраль.values():
        нейтралей[str(в)] = нейтралей.get(str(в), 0) + 1
    print(json.dumps(dict(
        речей=len(каталог), слів=len(слова), пар_звірено=len(каталог) * len(слова),
        жорстке_ні_пар=sum(map(len, ні.values())), вето_пулу_пар=sum(map(len, пул.values())),
        лише_пул_пар=sum(map(len, лише_пул.values())),
        лише_пул_речей=len({і for в in лише_пул.values() for і in в}),
        лише_ні_пар=sum(map(len, лише_ні.values())),
        нейтраль_з_lab=len(нейтраль), нейтралей=нейтралей,
        відбиток_ні=відбиток(ні), відбиток_пулу=відбиток(пул), відбиток_нейтралі=відбиток(нейтраль),
        точок_сітки=len(сітка), відбиток_сітки=відбиток(сітка)),
        ensure_ascii=False))
    if len(sys.argv) > 3:
        with gzip.open(sys.argv[3], "wt", encoding="utf-8") as ф:
            json.dump(dict(ні=ні, пул=пул, нейтраль=нейтраль), ф, ensure_ascii=False)
    return 0


if __name__ == "__main__":
    sys.exit(головна())
