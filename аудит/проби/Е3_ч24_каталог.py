"""Е3-одна-величина ч24 (п.6(г), рішення 07.11): ДО → ПІСЛЯ — читач «невідомо» з порівняння `fit.бік` у
`fit.py` (K-SHO-02, K-FIT-03 ×3, K-SIL-02, K-FIT-04) і `верхнє_суд.ремонтопридатність` (K-OUT-05).

Запуск із кореня репозиторію (каталог — розпакований `каталог_повний.xml.gz` у `джерела/`, ігнорується git):
    python3 аудит/проби/Е3_ч24_каталог.py                         # ПІСЛЯ: код цієї гілки
    git worktree add /tmp/до <SHA_ДО>
    python3 аудит/проби/Е3_ч24_каталог.py --код /tmp/до/джерела    # ДО: той самий скрипт на старому коді

Без моделі й платних API. Каталог розбирається довго: `--кеш <файл>` зберігає розібране (pickle) для повторів.
Речі каталогу проганяються на шести тілах (стенд, пісочний, яблуко, трикутник, два з виміряними коліном і литкою).
Вибірка: до `--ліміт` (1200) речей на слот, насіння 1; пари (взуття × низ, низ × верх, пальто × жакет) — до 300 × 300.
Друкує на кожне місце: що відповів `fit.бік` читачеві (1/−1 — доведено, None — «невідомо») і які знахідки цього
правила вийшли (правило, сила, коди заяв); «судиться» — відповідь доведена «так», «ні» — доведена «ні»,
«утримано» — знахідка «не судить», «мовчки» — «невідомо» без знахідки."""
import sys, pathlib, json, collections, os, io, contextlib, random, pickle, warnings
warnings.simplefilter("ignore")

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
def _арг(імʼя, типове=None):
    return sys.argv[sys.argv.index(імʼя) + 1] if імʼя in sys.argv else типове
код = pathlib.Path(_арг("--код", КОРІНЬ / "джерела")).resolve()
кеш = _арг("--кеш"); ліміт = int(_арг("--ліміт", 1200))
os.chdir(код); sys.path.insert(0, str(код))
import feed as Ф, bridge as B, composer as КМ, fit as ПС
import верхнє_суд as ВС

print(f"код: {код}")
if кеш and pathlib.Path(кеш).exists():
    кат = pickle.load(open(кеш, "rb"))
else:
    вх = json.load(open(код / "стенд_вх.json", encoding="utf-8"))
    вх["каталог"] = Ф.каталог_на_диску(str(КОРІНЬ / "джерела" / "каталог_повний.xml")); вх["гілка"] = 0
    with contextlib.redirect_stdout(io.StringIO()):
        json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
    кат = B.каталог_останнього_пакета()
    if кеш: pickle.dump(кат, open(кеш, "wb"))
_, T_стенд, _, _ = B._збірка(json.load(open(код / "стенд_вх.json", encoding="utf-8")))
ТІЛА = [("стенд", T_стенд)] + [(п, ПС.тіло(зр, обх)) for п, зр, обх in (
    ("пісочний", 168, dict(плечі=98, груди=92, талія=72, стегна=100)),
    ("яблуко", 160, dict(плечі=104, груди=104, талія=88, стегна=112)),
    ("трикутник", 170, dict(плечі=100, груди=96, талія=84, стегна=104)),
    ("литка виміряна", 168, dict(плечі=98, груди=92, талія=72, стегна=100, коліно=36, литка=40)),
    ("литка 2", 160, dict(плечі=104, груди=104, талія=88, стегна=112, коліно=34, литка=38)))]

ВИБІРКА = random.Random(1)
def вибірка(слоти, n=ліміт):
    р = [c for c in кат if c.get("слот") in слоти]
    ВИБІРКА.shuffle(р)
    return р[:n]
взуття, низи, верхи, шари = (вибірка({"взуття"}), вибірка({"низ", "сукня", "комплект"}),
                             вибірка({"верх"}), вибірка({"верхній_шар"}))
жакети = [c for c in кат if c.get("слот") == "верх" and c.get("тип") in ("блейзер", "костюм")]
пальта = шари[:300]; жакети = жакети[:300]

# Відповіді `fit.бік` читачеві: за функцією-читачем і місцем (різні виклики однієї функції — різні мітки).
відповіді = collections.Counter()
_бік = ПС.бік
def _лічильник(а, па, б, пб):
    в = _бік(а, па, б, пб)
    ф = sys._getframe(1).f_code.co_name
    мітка = {"смуга_шкіри": "K-SHO-02 смуга", "довжина_проти_зросту": "K-FIT-03 " + ("надлишок" if (б, пб) == (0.0, 0.0) else "слово"),
             "посадка_пояса": "K-FIT-04 схований", "ремонтопридатність": "K-OUT-05 жакет",
             "поділ_образу": "K-SIL-02 " + ("плечі" if (б, пб) != (0.0, 0.0) else "підлога")}.get(ф)
    if ф == "краї" and (б, пб) == (0.0, 0.0): мітка = "K-FIT-03 взуття вище підлоги"
    if мітка: відповіді[(мітка, {1: "1 (так)", -1: "−1 (ні)", None: "None (невідомо)"}[в])] += 1
    return в
ПС.бік = _лічильник

знахідки = collections.Counter()
ПРАВИЛА = ("K-SHO-02", "K-FIT-03", "K-SIL-02", "K-FIT-04", "K-OUT-05")
def облік(зн, мітка):
    for x in зн:
        if x.get("правило") not in ПРАВИЛА: continue
        коди = tuple(sorted(a.get("code") for a in (x.get("заяви") or ())))
        знахідки[(мітка, x["правило"], x["сила"], коди)] += 1

def річ(c, сл, T):
    return КМ.у_річ(dict(c), сл, T)

for п, T in ТІЛА:
    for c in взуття:
        р = річ(c, "взуття", T)
        облік(ПС.краї(T, [р]), "краї(взуття)"); облік(ПС.довжина_проти_зросту(T, [р]), "довжина_проти_зросту")
    for c in взуття:
        # через композитора взуття завжди з краєм «дефолт слота» (питання); халява картки — край «річ», як у гейтах
        if c.get("халява_см") is None: continue
        р = dict(річ(c, "взуття", T), верх_см=float(c["халява_см"]), низ_см=0.0, край_джерело="річ")
        облік(ПС.краї(T, [р]), "краї(взуття, халява картки)")
    for c in низи:
        р = річ(c, c["слот"], T)
        облік(ПС.краї(T, [р]), "краї(низ)"); облік(ПС.довжина_проти_зросту(T, [р]), "довжина_проти_зросту")
    for c in верхи:
        р = річ(c, "верх", T)
        облік(ПС.поділ_образу(T, [р]), "поділ_образу")
    рв = [річ(c, "взуття", T) for c in взуття[:300]]; рн = [річ(c, c["слот"], T) for c in низи[:300]]
    for в in рв[:150]:
        for н in рн[:150]:
            облік(ПС.смуга_шкіри(T, [н, в]), "смуга_шкіри")
    рв_ = [річ(c, "верх", T) for c in верхи[:150]]
    for н in рн[:150]:
        if not н.get("посадка"): continue
        for в in рв_:
            облік(ПС.посадка_пояса(T, [н, в], True), "посадка_пояса")
    рп = [річ(c, "верхній_шар", T) for c in пальта]; рж = [річ(c, "верх", T) for c in жакети]
    for а in рп:
        for ж in рж[:100]:
            облік(ВС.ремонтопридатність([а, ж], T), "ремонтопридатність")

print("\n── відповіді fit.бік читачам (усі тіла, усі пари) ──")
for (м, в), n in sorted(відповіді.items()): print(f"   {м:32s} {в:16s} {n}")
print("\n── знахідки читачів (мітка · правило · сила · коди заяв) ──")
for (м, пр, си, кд), n in sorted(знахідки.items()): print(f"   {м:22s} {пр:9s} {си:8s} {','.join(кд) or '—':45s} {n}")
