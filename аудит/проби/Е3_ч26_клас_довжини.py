# -*- coding: utf-8 -*-
"""Е3-одна-величина ч26 (п.7, клас довжини → точка речі на тілі): довжина й край речей на тілах стенда ДО → ПІСЛЯ.

Запуск із кореня репозиторію:
    python3 аудит/проби/Е3_ч26_клас_довжини.py                       # ПІСЛЯ: код цієї гілки
    git worktree add /tmp/до <SHA_ДО>
    python3 аудит/проби/Е3_ч26_клас_довжини.py --код /tmp/до/джерела  # ДО: той самий скрипт на старому коді

Каталог — `джерела/каталог_повний.xml` цього клону через живий `bridge.виклик("запити")` стенда (як
`Е3_ч21_точка_речі.py`); модель і платні API не викликаються. Тіла — 155/165/175 см, обхвати стенда 98/92/74/100,
похибки рівнів — з `fit.тіло`. Друкує:
  · шкалу класів довжини композитора (`висота_рівня`): центр і півширина на кожному тілі;
  · слова генеративної сітки (`силует_запит.ДОВЖИНИ_*`): висота краю на кожному тілі;
  · речі зі словом довжини без довжини виробу (край «слово»): (зріст, клас, півширина, похибка краю, смуга графа);
  · K-FIT-03 `fit.краї` по одній речі, `fit.довжина_проти_зросту`, K-SIL-02 `fit.поділ_образу` по одній верхній речі;
  · клас поділу з довжини виробу (`довжина_клас_виміряний`, між класами) і чи він став `довжина_рівень`;
  · халява взуття: (рівень, похибка `fit.похибка_слова` відома)."""
import sys, pathlib, json, collections, os, io, contextlib

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
код = pathlib.Path(sys.argv[sys.argv.index("--код") + 1]).resolve() if "--код" in sys.argv else КОРІНЬ / "джерела"
os.chdir(код); sys.path.insert(0, str(код))
import feed as Ф, bridge as B, composer as КМ, fit as ПС, graph as Г, композитор_річ as КР, силует_запит as S

вх = json.load(open(код / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску(str(КОРІНЬ / "джерела" / "каталог_повний.xml")); вх["гілка"] = 0
with contextlib.redirect_stdout(io.StringIO()):
    json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
print(f"код: {код}  · речей каталогу {len(кат)}")


def друк(назва, л, n=60):
    print(f"{назва}:")
    for к, v in sorted(л.items(), key=lambda x: (str(x[0][0]) if isinstance(x[0], tuple) else "", -x[1], str(x[0])))[:n]:
        print(f"   {v:6d}  {к}")


def ключ(z):
    return (z["правило"], z["сила"], tuple(sorted(з["code"] for з in (z.get("заяви") or []))))


ОБХВАТИ = dict(плечі=98, груди=92, талія=74, стегна=100)
ТІЛА = {зр: ПС.тіло(зр, ОБХВАТИ) for зр in (155, 165, 175)}
print("шкала класів (висота_рівня): клас → центр см ± півширина на 155 / 165 / 175")
for клас in КР.РІВЕНЬ_ЗОНА:
    print("   %-10s %s" % (клас, " / ".join("%s ± %s" % КР.висота_рівня(клас, t["висоти"]) for t in ТІЛА.values())))
print("генеративна сітка (силует_запит): слово → край см на 155 / 165 / 175")
for сл, т in S.ДОВЖИНИ_ВЕРХУ + S.ДОВЖИНИ_НИЗУ:
    print("   %-9s %-26s %s" % (сл, т, " / ".join(
        str(S.висота_довжини(т, t["висоти"]) if hasattr(S, "висота_довжини") else (round(t["висоти"][т], 1), "—"))
        for t in ТІЛА.values())))

слово = [c for c in кат if c.get("довжина_рівень") and c.get("довжина_виробу_см") is None
         and c.get("слот") in ("низ", "сукня", "комплект", "верхній_шар", "верх")]
виріб = [c for c in кат if c.get("довжина_виробу_см") is not None
         and c.get("слот") in ("низ", "сукня", "комплект", "верхній_шар", "верх")]
print(f"речей зі словом довжини без довжини виробу: {len(слово)}; з довжиною виробу: {len(виріб)}")
краї, k03, k03к, k02, клас, халява = (collections.Counter() for _ in range(6))
for зр, t in ТІЛА.items():
    with contextlib.redirect_stdout(io.StringIO()):
        рс = [р for р in (КМ.у_річ(dict(c), c["слот"], t) for c in слово) if р]
        рв = [р for р in (КМ.у_річ(dict(c), c["слот"], t) for c in виріб) if р]
        for р in рс:
            пк = ПС.похибка_краю(t, р)
            краї[(зр, р.get("довжина_рівень"), р.get("край_джерело"), р.get("край_розкид_см"),
                  "похибка краю відома" if пк is not None else "похибка краю невідома",
                  "смуга в графі" if "край" in Г.зона(р) else "смуги нема")] += 1
            for z in ПС.краї(t, [р]):
                k03к[(зр,) + ключ(z)] += 1
            if р.get("слот") in ("верх", "верхній_шар"):
                for z in ПС.поділ_образу(t, [р]):
                    k02[(зр,) + ключ(z)] += 1
        for z in ПС.довжина_проти_зросту(t, рв):
            k03[(зр,) + ключ(z)] += 1
        for р in рв:
            клас[(зр, р.get("довжина_клас_виміряний"), "між класами" if р.get("довжина_клас_між") else "у класі",
                  "клас → довжина_рівень" if str(р.get("довжина_джерело") or "").startswith("вимір") else "")] += 1
    for c in кат:
        if c.get("слот") == "взуття" and c.get("халява_рівень"):
            халява[(зр, c.get("халява_рівень"), "похибка відома" if ПС.похибка_слова(t, c["халява_рівень"]) is not None
                    else "похибка невідома")] += 1
друк("край зі слова: (зріст, клас, джерело краю, півширина, похибка краю, смуга графа)", краї)
друк("K-FIT-03 fit.краї по одній речі зі словом: (зріст, правило, сила, заяви)", k03к)
друк("K-SIL-02 fit.поділ_образу по одній верхній речі зі словом: (зріст, правило, сила, заяви)", k02)
друк("K-FIT-03 довжина_проти_зросту (речі з довжиною виробу): (зріст, правило, сила, заяви)", k03)
друк("клас поділу з довжини виробу: (зріст, клас, між, записано)", клас)
друк("халява взуття: (зріст, рівень, похибка слова)", халява)
