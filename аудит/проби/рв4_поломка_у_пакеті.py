# -*- coding: utf-8 -*-
"""РВ-4 · чи названа поломка руки 2 доїжджає до МОДЕЛІ — на 12 сідах, з паспортом виклику 0.

Рядок 17 дошки казав: «контроль сліпий (`різних=0`) на 5 сідах із 12». `різних`
рахує ЛИШЕ рядки брифа, а три поломки з шести («температура», «година»,
«доречність») рухають ВИПАДОК, не правила, — тож нуль там означав сліпий прилад,
а не сліпий прогін. Проба друкує обидва числа поруч: рядки брифа і поля ПАКЕТ_V1,
якими рука 2 відрізняється від руки 1 (`мета.контроль.слід`; пул поза ним — його
переставляє `СІЛЬ_РУКИ_2` на кожному сіді). Плюс `без_входу`: чого жереб цього
прогону взяти не міг і з якої причини.
Запуск із теки `джерела`: python3 ../аудит/проби/рв4_поломка_у_пакеті.py
"""
import json
import sys

sys.path.insert(0, ".")
import bridge as B  # noqa: E402

ПАСПОРТ_МОДЕЛІ = {   # дослівно з тест_живого_шляху.py
    "подія": "робочий день в офісі", "формат": "приміщення", "тривалість_год": 9,
    "рух": "сидіти", "дрес_код": "business_casual", "ошатність": [4, 6],
    "година": 9, "темп_c": 18, "опади": "ні", "намір": "conventional",
    "бажання": ["щось зі структурою"],
    "вето": {"типи": [], "тканини": [], "принти": [], "кольори": [], "зони": []},
    "ноги_вище_см": None, "настрій": ["зібрано"], "невідомо": ["взуття"],
}
вх = json.load(open("стенд_вх.json"))
вх.update(каталог="каталог_brief.xml", без_фото=1, варіантів=3)
п = json.loads(B.виклик("паспорт", json.dumps(
    dict(json_моделі=json.dumps(ПАСПОРТ_МОДЕЛІ, ensure_ascii=False),
         сценарій=вх["сценарій"], вимоги=""), ensure_ascii=False)))
пасп = п["паспорт"]
print("паспорт виклику 0: нагода=%s · година=%s · темп_c=%s" % (
    пасп.get("нагода"), пасп.get("година"), пасп.get("темп_c")))
сліпих, підсумок = 0, {}
for сід in range(12):
    r = json.loads(B.виклик("запити", json.dumps(dict(вх, сід=сід, паспорт=пасп), ensure_ascii=False)))
    к, пол = r["мета"]["контроль"], r["поломка"]
    сліпих += bool(к["сліпий"])
    підсумок.setdefault(к["поломка"], []).append(bool(к["сліпий"]))
    print("сід %2d · %-12s · різних_правил %d · сліпий: %-3s · без_входу: %-4s · слід у пакеті: %s"
          % (сід, к["поломка"], к["різних"], "так" if к["сліпий"] else "ні",
             "—" if not к["без_входу"] else ",".join(sorted(к["без_входу"])),
             ", ".join(к["слід"] or []) or "—"))
    print("       що_змінено: %s" % (пол.get("що_змінено") or "—"))
print()
for назва, рядки in sorted(підсумок.items()):
    print("%-12s · сідів %d · сліпих: %d" % (назва, len(рядки), sum(рядки)))
print("УСЬОГО сліпих сідів: %d із 12" % сліпих)
