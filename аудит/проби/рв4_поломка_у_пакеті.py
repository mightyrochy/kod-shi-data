# -*- coding: utf-8 -*-
"""РВ-4 · чи поломка руки 2 доїжджає в ПАКЕТ_V1 на ЖИВОМУ шляху — з паспортом виклику 0.

С-51 (Т-11 крок 2) зробила `_зіпсувати_паспорт`, бо паспорт переважає сценарій і
доти скасовував поломки «температура», «година», «доречність». Проба С-51 міряла
це на одному сіді й одній поломці (година, сід 3). Тут міряється те, що справді
бачить модель: поле `випадок` пакетів B (рука 1) і C (рука 2) на 12 сідах, з
паспортом, зібраним так само, як у `тест_живого_шляху.py` (виклик 0 на
синтетичному JSON моделі).
Запуск із теки `джерела`: python3 ../аудит/проби/рв4_поломка_у_пакеті.py
"""
import json
import sys

sys.path.insert(0, ".")
import bridge as B  # noqa: E402

ПАСПОРТ_МОДЕЛІ = {   # дослівно з тест_живого_шляху.py
    "подія": "робочий день в офісі", "формат": "приміщення", "тривалість_год": 9,
    "рух": "сидіти", "дрес_код": "business_casual", "ошатність": [4, 6],
    "година": 9, "темп_c": 18, "опади": "ні", "намір": "conventional",
    "бажання": ["щось зі структурою"],
    "вето": {"типи": [], "тканини": [], "принти": [], "кольори": [], "зони": []},
    "ноги_вище_см": None, "настрій": ["зібрано"], "невідомо": ["взуття"],
}
вх = json.load(open("стенд_вх.json"))
вх.update(каталог="каталог_brief.xml", без_фото=1, варіантів=3)
п = json.loads(B.виклик("паспорт", json.dumps(
    dict(json_моделі=json.dumps(ПАСПОРТ_МОДЕЛІ, ensure_ascii=False),
         сценарій=вх["сценарій"], вимоги=""), ensure_ascii=False)))
пасп = п["паспорт"]
print("паспорт виклику 0: джерело=%s · подія=«%s» · нагода=%s · місце=%s · година=%s · темп_c=%s"
      % (пасп.get("джерело"), пасп.get("подія"), пасп.get("нагода"), пасп.get("місце"),
         пасп.get("година"), пасп.get("темп_c")))
print()
підсумок = {}
for сід in range(12):
    r = json.loads(B.виклик("запити", json.dumps(dict(вх, сід=сід, паспорт=пасп), ensure_ascii=False)))
    Bв = json.loads(r["B"])["випадок"]
    Cв = json.loads(r["C"])["випадок"]
    різні = sorted(k for k in set(Bв) | set(Cв) if Bв.get(k) != Cв.get(k))
    пол, к = r["поломка"], r["мета"]["контроль"]
    підсумок.setdefault(пол["назва"], []).append((сід, різні, к["різних"]))
    print("сід %2d · %-12s · %-28s · різних_правил %d · випадок B≠C у: %s"
          % (сід, пол["назва"], (пол.get("що_змінено") or "")[:28], к["різних"], ", ".join(різні) or "—"))
    if пол["назва"] == "доречність":
        print("       B: подія=«%s» нагода=%s місце=%s рядок=«%s»"
              % (Bв.get("подія"), Bв.get("нагода"), Bв.get("місце"), Bв.get("рядок")))
        print("       C: подія=«%s» нагода=%s місце=%s рядок=«%s»  ← подія (її слова) %s"
              % (Cв.get("подія"), Cв.get("нагода"), Cв.get("місце"), Cв.get("рядок"),
                 "НЕ ЗМІНИЛАСЬ: модель дістає подію про одне, а нагоду й рядок про інше"
                 if Cв.get("подія") == Bв.get("подія") else "змінилась"))
print()
for назва, рядки in sorted(підсумок.items()):
    print("%-12s · сідів %d · випадок пакета різниться: %s · контроль сліпий (різних=0): %d із %d"
          % (назва, len(рядки),
             "так" if all(р[1] for р in рядки) else ("ні" if not any(р[1] for р in рядки) else "не завжди"),
             sum(1 for р in рядки if р[2] == 0), len(рядки)))
