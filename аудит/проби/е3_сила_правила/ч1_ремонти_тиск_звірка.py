# -*- coding: utf-8 -*-
"""Е3-сила-правила, п.1а, частина 1: звірка K-COL-JOIN (`колір_ремонти`) і R-CHEV-14 (`палітра_запити`)
до й після переведення на `реєстр_сила.зн`.

Запуск із кореня репозиторію:
  python3 аудит/проби/е3_сила_правила/ч1_ремонти_тиск_звірка.py --знімок <дерево> > знімок.json
  python3 аудит/проби/е3_сила_правила/ч1_ремонти_тиск_звірка.py --порівняти ДО.json ПІСЛЯ.json

<дерево> — корінь робочого дерева (база — `git worktree add /tmp/база <sha>`, каталоги — посилання на
розпаковані в `джерела/`). Знімок кличе функції продукту:
  · `колір_ремонти.несумісні_ремонти` — синтетичні знахідки з вікнами на одному носії: дві вимоги,
    альтернативи, дві осі, носій «верх|шарф», три правила, конфлікт (контроль K-COL-CONF); вихід — і
    сирий, і після `обмежити_вагу` (як у `суд_огляд.review`), з `pipeline.питання_або_нуль`;
  · `палітра_запити.тиск_знахідка` — сітка тонів речі 0…357° крок 3 × 6 тонів шкіри × слот/роль;
  · ендпойнт `запити` (`bridge.виклик`) на стенді `стенд_вх.json` для 4 гілок × 2 джерел фото:
    відповідь і специфікація пакета; знахідки R-CHEV-14 у них зводяться до мітки, а решта —
    байт у байт; окремо — тиск дуг (`тиск_центр`, `тиск_межі`) і рядків фіду.
"""
import json
import os
import sys


def _без_rchev(x, знайдені):
    if isinstance(x, dict):
        if x.get("правило") == "R-CHEV-14":
            знайдені.append(x)
            return "<R-CHEV-14>"
        return {к: _без_rchev(в, знайдені) for к, в in x.items()}
    if isinstance(x, list):
        return [_без_rchev(в, знайдені) for в in x]
    return x


def _тиски(x, вих, шлях=""):
    if isinstance(x, dict):
        for к, в in x.items():
            if к in ("тиск_центр", "тиск_межі"):
                вих.append([шлях + "/" + к, в])
            else:
                _тиски(в, вих, шлях + "/" + str(к))
    elif isinstance(x, list):
        for і, в in enumerate(x):
            _тиски(в, вих, шлях + "/%d" % і)


def _знімок(дерево):
    корінь = os.path.join(os.path.abspath(дерево), "джерела")
    sys.path.insert(0, корінь)
    os.chdir(корінь)
    import warnings
    warnings.simplefilter("ignore")
    import колір_ремонти as KR
    import палітра_запити as PZ
    import реєстр_сила as RS
    import pipeline as PL
    import bridge as B

    def з(правило, слот, **вікна):
        return dict(правило=правило, сила="soft", запит_у_каталог=dict(слот=слот, **вікна))

    випадки = {
        "дві вимоги L": [з("K-CLR-02", "шарф", цільова_L=[48, 90]), з("K-KOH-06", "шарф", цільова_L=[20, 76])],
        "альтернативи": [з("K-CLR-02", "верх", цільова_L_темніше=[20, 40], цільова_L_світліше=[60, 80]),
                         з("K-KOH-06", "верх", цільова_L=[30, 70])],
        "дві осі": [з("K-CLR-02", "сумка", цільова_L=[40, 80], цільова_C=[10, 30]),
                    з("K-COL-02", "сумка", цільова_L=[30, 60], цільова_C=[5, 20])],
        "два носії": [з("K-CLR-02", "верх|шарф", цільова_L=[48, 90]), з("K-KOH-06", "шарф", цільова_L=[20, 76]),
                      з("K-COL-02", "верх", цільова_C=[5, 20]), з("K-COL-06", "верх", цільова_C=[0, 15])],
        "три правила": [з("K-CLR-02", "низ", цільова_L=[30, 90]), з("K-KOH-06", "низ", цільова_L=[20, 70]),
                        з("K-COL-01", "низ", цільова_L=[40, 60], цільове_b=[0, 10])],
        "конфлікт (контроль)": [з("K-CLR-02", "шарф", цільова_L=[60, 90]), з("K-KOH-06", "шарф", цільова_L=[20, 50])],
    }
    join = {}
    for назва, зн in випадки.items():
        сирі = KR.несумісні_ремонти(зн)
        join[назва] = dict(сирі=сирі, після_ваги=RS.обмежити_вагу([dict(x) for x in сирі]),
                           питання_або_нуль=[PL.питання_або_нуль(x) for x in сирі])

    тиск = {}
    for hs in (10, 25, 40, 55, 70, 200):
        for hr in range(0, 360, 3):
            тиск["%d/%d" % (hs, hr)] = PZ.тиск_знахідка(hr, hs, слот="верх", роль="біля_обличчя")
    тиск["без шкіри"] = PZ.тиск_знахідка(30, None)

    вх0 = json.load(open("стенд_вх.json", encoding="utf-8"))
    стенд = {}
    for гілка in range(4):
        for джерело in ("uncontrolled", "protocolized"):
            вх = dict(вх0, гілка=гілка, source=джерело)
            r = json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
            спец, запити = B.спец_останнього_пакета()
            знайдені, тиски = [], []
            решта = _без_rchev(dict(r=r, спец=спец, запити=запити), знайдені)
            _тиски(dict(спец=спец, запити=запити), тиски)
            стенд["%d/%s" % (гілка, джерело)] = dict(решта=решта, rchev=знайдені, тиски=тиски)
    return dict(join=join, тиск=тиск, стенд=стенд)


def _різниця_знахідок(до, після):
    """{ключ: [кількість змін, приклад ДО, приклад ПІСЛЯ]} для пар знахідок."""
    зміни = {}
    for a, b in zip(до, після):
        if a is None or b is None:
            if a != b:
                зміни.setdefault("<сама знахідка>", [0, a, b])[0] += 1
            continue
        for к in sorted(set(a) | set(b)):
            if a.get(к) != b.get(к):
                з = зміни.setdefault(к, [0, a.get(к, "<нема>"), b.get(к, "<нема>")])
                з[0] += 1
    return зміни


def _порівняти(до, після):
    рез = {}
    рез["join"] = {н: dict(
        сирі=_різниця_знахідок(до["join"][н]["сирі"], після["join"][н]["сирі"]),
        після_ваги=_різниця_знахідок(до["join"][н]["після_ваги"], після["join"][н]["після_ваги"]),
        кількість=[len(до["join"][н]["сирі"]), len(після["join"][н]["сирі"])],
        питання_або_нуль=[до["join"][н]["питання_або_нуль"], після["join"][н]["питання_або_нуль"]])
        for н in до["join"]}
    кл = sorted(до["тиск"])
    рез["тиск"] = dict(точок=len(кл), знахідок=[sum(1 for к in кл if до["тиск"][к]),
                                               sum(1 for к in кл if після["тиск"][к])],
                       зміни=_різниця_знахідок([до["тиск"][к] for к in кл], [після["тиск"][к] for к in кл]),
                       тиск_дорівнює_старій_вазі=all(
                           (до["тиск"][к] is None and після["тиск"][к] is None)
                           or (після["тиск"][к]["тиск"] == до["тиск"][к]["сила_нп"]) for к in кл))
    рез["стенд"] = {}
    for к in до["стенд"]:
        a, b = до["стенд"][к], після["стенд"][к]
        рез["стенд"][к] = dict(
            решта_тотожна=a["решта"] == b["решта"],
            тиски_тотожні=a["тиски"] == b["тиски"], тисків=len(a["тиски"]),
            rchev=[len(a["rchev"]), len(b["rchev"])],
            зміни_rchev={кл: v[0] for кл, v in _різниця_знахідок(a["rchev"], b["rchev"]).items()})
    return рез


if __name__ == "__main__":
    if sys.argv[1:2] == ["--знімок"]:
        json.dump(_знімок(sys.argv[2]), sys.stdout, ensure_ascii=False, sort_keys=True, default=str)
    elif sys.argv[1:2] == ["--порівняти"]:
        до = json.load(open(sys.argv[2], encoding="utf-8"))
        після = json.load(open(sys.argv[3], encoding="utf-8"))
        json.dump(_порівняти(до, після), sys.stdout, ensure_ascii=False, indent=1, sort_keys=True, default=str)
    else:
        sys.exit(__doc__)
