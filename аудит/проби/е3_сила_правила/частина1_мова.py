"""Порівняти мовний гейт з базою на кейсах і всіх назвах та описах каталогу.

Запуск: python аудит/проби/е3_сила_правила/частина1_мова.py [SHA бази].
Старий модуль виконується з поточними залежностями, окреме старе дерево не запускається.
"""
import json
from pathlib import Path
import subprocess
import sys
import types

КОРІНЬ = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(КОРІНЬ / "джерела"))
import feed
import language_gate as мова
import реєстр_правил as реєстр


def мірило(база):
    """Звірити старі поля, нові поля конструктора й реакцію всіх чотирьох емісій на T3."""
    джерело = subprocess.check_output(
        ["git", "show", база + ":джерела/language_gate.py"], cwd=КОРІНЬ).decode("utf-8")
    стара = types.ModuleType("мовний_гейт_бази")
    exec(compile(джерело, "мовний_гейт_бази", "exec"), стара.__dict__)
    кейси = [(т, []) for т, *_ in мова._КЕЙСИ]
    кейси += [(т, ц) for т, ц, *_ in мова._КЕЙСИ_ЦІЛІ]
    кейси += [(т, []) for т in (
        "Брюки и сапоги в тон, сумка через плечо", "Камуфляжний принт цього сезону",
        "Рятуємо вас від перевантаження вибором", "Шелдон і соматотипи",
        "Золотий перетин 1.618", "Ціль WHR 0.7", "Капсула на 33 речі",
        "82% речей носять менше 3 разів на рік")]
    предмети = feed.читати_yml(feed.каталог_на_диску())[0]
    тексти = sorted({str(р.get(п) or "") for р in предмети
                     for п in ("назва", "опис")} - {""})
    емісій, доповнені_причини = 0, {}
    for текст, цілі in кейси + [(т, []) for т in тексти]:
        for режим in ("блокувати", "мітити"):
            до = стара._перевірити_обчислити(текст, режим, цілі)
            після = мова._перевірити_обчислити(текст, режим, цілі)
            for поле in ("порушення", "карантин"):
                assert len(до[поле]) == len(після[поле]), (текст, поле)
                for старе, нове in zip(до[поле], після[поле]):
                    assert all(нове[к] == в for к, в in старе.items() if к != "чому"), (текст, старе, нове)
                    if "чому" in старе and нове["чому"] != старе["чому"]:
                        assert нове["чому"].startswith(старе["чому"]) and нове.get("поза_корпусом")
                        доповнені_причини[нове["правило"]] = нове["поза_корпусом"]
                    assert {"сила_нп", "сила_нп_джерело", "блокує", "регістр", "речі", "чому"} <= нове.keys()
                    емісій += 1
            assert all(до[к] == після[к] for к in до if к not in ("порушення", "карантин")), текст
    тіри = []
    for текст, поле, правило in (
        ("Ця сумка читається дорого", "порушення", "K-SIG-01"),
        ("Kibbe радить довгі лінії", "порушення", "R-TYP-05"),
        ("Камуфляжний принт цього сезону", "карантин", "R-PRN-09"),
        ("Красивые брюки", "порушення", мова.ЯРУС_УКРАЇНСЬКОЇ)):
        реєстр.REGISTRY["проба_мовної_стелі"] = dict(t="T3", val=1, прав=[правило])
        try:
            до = next(з for з in стара._перевірити_обчислити(текст)[поле] if з["правило"] == правило)
            після = next(з for з in мова._перевірити_обчислити(текст)[поле] if з["правило"] == правило)
            assert після["сила"] == ("hint" if поле == "карантин" else "soft")
            тіри.append(dict(правило=правило, до=до["сила"], після=після["сила"]))
        finally:
            del реєстр.REGISTRY["проба_мовної_стелі"]
    мова._КЕШ_ВЕРДИКТІВ.clear()
    перший = мова.перевірити("Ця сумка читається дорого")
    перший["порушення"][0]["речі"].append("зміна копії")
    assert мова.перевірити("Ця сумка читається дорого")["порушення"][0]["речі"] == []
    return dict(база=база, речей=len(предмети), текстів_каталогу=len(тексти),
                кейсів=len(кейси), режимів=2, емісій=емісій, змін_рішень_збігів_позицій=0,
                доповнені_причини=доповнені_причини,
                тіри=тіри, кеш="копії незалежні", обмеження=__doc__)


if __name__ == "__main__":
    print(json.dumps(мірило(sys.argv[1] if len(sys.argv) > 1 else
                          "47e17eadcf1be7ab11fe020edcf3de4604d2ba6a"), ensure_ascii=False, indent=2))
