# -*- coding: utf-8 -*-
"""Е3-сила-правила, п.1б–в: звірка `реєстр_сила.перезважити` з тим, що робили місця доти.

Запуск із кореня репозиторію:
  python3 аудит/проби/е3_сила_правила/перезважити_звірка.py <дерево> > вихід.json   — знімок одного дерева
  python3 аудит/проби/е3_сила_правила/перезважити_звірка.py --порівняти ДО.json ПІСЛЯ.json

<дерево> — корінь робочого дерева (база — `git worktree add /tmp/база origin/main`). Знімок кличе ті
самі функції продукту на синтетичних знахідках, без моделей і каталогу:
  · `зн` — сітка правил політики й ядра × п'ять сил × ремонт/поріг × реєстри модулів (рефакторинг
    конструктора: очікується тотожність);
  · `гейт_наміром`, `намір_доречності`, `обмежити_слабшу_вісь`, `регістр_оправи`, `_на_еластані`,
    `над_дефолтним_кроєм` — кожне місце п.1б–в, яке крок перевів на `перезважити`;
  · знахідки K-KOH-02 «питання» й K-INT-04, з яких місця `поломки` і `суд_інтерес` знімали
    регістр, поставлений руками.
Порівняння друкує на кожен випадок «тотожно» чи ключі, що змінились, і значення ДО → ПІСЛЯ.
"""
import json
import os
import sys


def _знімок(дерево):
    sys.path.insert(0, os.path.join(os.path.abspath(дерево), "джерела"))
    os.chdir(os.path.join(os.path.abspath(дерево), "джерела"))
    import warnings
    warnings.simplefilter("ignore")
    import реєстр_сила as RS
    import реєстр_політика as RP
    import реєстр_намір as RN
    import реєстр_осі as RO
    import суд_намір as SN
    import аксесуари_розмір as AR
    import аксесуари_реєстр as AREG
    import fit as FIT
    import верхнє_реєстр as VR
    import силует_пропорції as SP
    import силует_крої as SK

    СИЛИ = ("hard", "strong", "default", "soft", "hint")
    вих = {}

    def з(п, с, **kw):
        return RS.зн(п, с, "суть правила %s — хвіст" % п, ["річ а", "річ б"], "чому %s" % п, **kw)

    # 1) конструктор: рефакторинг `зн` мусить дати ті самі знахідки
    правила = sorted(set(RP.ПОЛІТИКА_РЕГІСТРУ) | {"K-KOH-05", "K-COL-06-T", "K-CLR-02", "K-EYE-02",
                                                   "K-BOD-02", "K-INT-04", "K-KOH-02", "K-FIT-04", "K-WEA-05"})
    реєстри = {"ядро": None, "аксесуари": AREG.РЕЄСТР, "fit": FIT.РЕЄСТР, "верхнє": VR.РЕЄСТР}
    for п in правила:
        for с in СИЛИ + ("питання", "утримано"):
            for нр, reg in реєстри.items():
                вих["зн|%s|%s|%s" % (п, с, нр)] = з(п, с, ремонт=["ремонт %s" % п], reg=reg)
            вих["зн|%s|%s|поріг" % (п, с)] = з(п, с, ремонт="Ремонт рядком", поріг=2.0, вимір=3.1)

    # 2) гейт наміру: рахункова знахідка за нестандартного наміру → hint
    for п in ("K-COL-01", "K-COL-02", "K-COL-05", "K-COMP-03", "K-CRA-01", "K-CRA-02", "K-KOH-05"):
        for с in СИЛИ:
            вих["гейт_наміром|%s|%s" % (п, с)] = RN.гейт_наміром(з(п, с, ремонт=["р"]), "editorial")

    # 3) намір доречності: K-KOH-05 hint/soft → hard
    for с in ("hint", "soft", "default"):
        for нп in (0.3, 0.7):
            z = dict(з("K-KOH-05", с, ремонт=["зсунути образ"], поріг=2.0, вимір=3.0), сила_нп=нп)
            вих["намір_доречності|%s|%s" % (с, нп)] = SN.намір_доречності([z], "context_optimal")[0]

    # 4) слабша вісь: K-COL-06-T під контрастною K-CLR-02 тієї самої речі
    for с in СИЛИ + ("питання",):
        пара = [dict(правило="K-CLR-02", сила=с, речі=["в"]), з("K-COL-06-T", "soft")]
        пара[1]["речі"] = ["в"]
        вих["слабша_вісь|%s" % с] = RO.обмежити_слабшу_вісь(пара, "protocolized")
        пара = [dict(правило="K-CLR-02", сила=с, речі=["в"]),
                dict(правило="K-COL-06-T", сила="soft", речі=["в"], сила_нп=0.5)]   # запис стенда гейтів
        вих["слабша_вісь_стенд|%s" % с] = RO.обмежити_слабшу_вісь(пара, "protocolized")

    # 5) оправа: естетика K-EYE-02 → hint
    for с in СИЛИ:
        вих["оправа|%s" % с] = AR.регістр_оправи([AREG.зн("K-EYE-02", с, "оправа", ["о"], "форма",
                                                           ремонт=["інша оправа"])])

    # 6) еластан: K-BOD-02 на крок нижче
    for с in СИЛИ:
        for вимір in (None, 5.0):
            z = з("K-BOD-02", с, ремонт=["інший крій"], **({} if вимір is None else dict(поріг=2.0, вимір=вимір)))
            вих["еластан|%s|%s" % (с, вимір)] = SP._на_еластані(z, 5.0, ["склад"])

    # 7) дефолтний крій: будь-яка знахідка силуету → питання
    for п in ("K-BOD-02", "K-SIL-01", "K-SIL-03"):
        for с in СИЛИ:
            вих["дефолтний_крій|%s|%s" % (п, с)] = SK.над_дефолтним_кроєм(
                з(п, с, ремонт=["р"], поріг=2.0, вимір=3.0), ["сукня"])

    # 8) регістр, який місця ставили руками поверх конструктора
    вих["поломки|K-KOH-02|питання"] = RS.зн("K-KOH-02", "питання", "item_formality_unknown", ["р"],
                                           "item_formality_unknown")
    вих["інтерес|K-INT-04|hard"] = RS.зн("K-INT-04", "hard", "с", ["р"], "ч", ремонт=["р"],
                                        поріг=1.0, вимір=0.0)
    return вих


def _порівняти(до, після):
    до, після = json.load(open(до, encoding="utf-8")), json.load(open(після, encoding="utf-8"))
    тотожно, різні = 0, {}
    for к in sorted(set(до) | set(після)):
        а, б = до.get(к), після.get(к)
        if а == б:
            тотожно += 1
            continue
        if isinstance(а, list) and isinstance(б, list) and len(а) == len(б):
            пари = [(x, y) for x, y in zip(а, б) if x != y]
        else:
            пари = [(а, б)]
        зміни = {}
        for x, y in пари:
            x, y = x or {}, y or {}
            for поле in sorted(set(x) | set(y)):
                if x.get(поле) != y.get(поле):
                    зміни[поле] = [x.get(поле), y.get(поле)]
        різні[к] = зміни
    за_групою = {}
    for к in різні:
        за_групою[к.split("|")[0]] = за_групою.get(к.split("|")[0], 0) + 1
    всього = {}
    for к in set(до) | set(після):
        всього[к.split("|")[0]] = всього.get(к.split("|")[0], 0) + 1
    return dict(випадків=len(set(до) | set(після)), тотожно=тотожно, змінено=len(різні),
                групи={г: dict(випадків=всього[г], змінено=за_групою.get(г, 0)) for г in sorted(всього)},
                зміни=різні)


if __name__ == "__main__":
    if sys.argv[1] == "--порівняти":
        print(json.dumps(_порівняти(sys.argv[2], sys.argv[3]), ensure_ascii=False, indent=1, sort_keys=True))
    else:
        print(json.dumps(_знімок(sys.argv[1]), ensure_ascii=False, indent=None, sort_keys=True, default=str))
