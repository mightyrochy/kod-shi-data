"""Порівнює мовний гейт з базою на формулах і назвах усього каталогу.

Запуск із кореня: python аудит/проби/е3_сила_правила/мова_конструктор.py [SHA бази].
Тимчасова константа T3 перевіряє стелю кожного з чотирьох виходів; у продукт її не записуємо.
"""
import collections
import json
import pathlib
import subprocess
import sys
import types


def головна():
    """Звіряє рішення, предметні поля й проходження всіх виходів через конструктор."""
    корінь = pathlib.Path(__file__).resolve().parents[3]
    sys.path.insert(0, str(корінь / 'джерела'))
    import feed
    import чистка_каталогу
    import language_gate as нова
    import реєстр_правил as реєстр
    база = sys.argv[1] if len(sys.argv) > 1 else 'f5975dcd9c2e508a32bc3dab988d37c9a06b2d5b'
    стара = types.ModuleType('мова_до')
    код = subprocess.check_output(['git', 'show', база + ':джерела/language_gate.py'], cwd=корінь).decode('utf-8')
    exec(compile(код, 'language_gate@' + база, 'exec'), стара.__dict__)
    чистка_каталогу.забезпечити_чистим('каталог_повний.xml')
    речі = feed.читати_yml(feed.каталог_на_диску())[0]
    формули = [т for т, _, _ in нова._КЕЙСИ] + [
        'Рятуємо вас від перевантаження вибором', 'Камуфляжний принт цього сезону',
        'Красивое платье', 'Брюки и сапоги в тон, сумка через плечо',
        'Поділ ставимо за золотим перетином 1.618', 'Ціль — WHR 0.7, це ідеал']
    назви = sorted({str(р.get('назва') or '') for р in речі} - {''})
    зміни_сили = collections.Counter()
    правила = collections.Counter()
    знахідок = 0
    for номер, текст in enumerate(формули + назви):
        if номер % 5000 == 0:
            print('Звірено текстів:', номер, flush=True)
        for режим, цілі in [('блокувати', None), ('мітити', ['стегна'])]:
            до = стара._перевірити_обчислити(текст, режим, цілі)
            після = нова._перевірити_обчислити(текст, режим, цілі)
            for поле in до.keys() - {'порушення', 'карантин'}:
                assert до[поле] == після[поле], (текст, поле, до[поле], після[поле])
            for поле in ('порушення', 'карантин'):
                assert len(до[поле]) == len(після[поле]), (текст, поле)
                for д, п in zip(до[поле], після[поле]):
                    for к in д.keys() - {'сила', 'чому'}:
                        assert д[к] == п[к], (текст, к, д[к], п[к])
                    assert {'речі', 'чому', 'регістр', 'сила_нп', 'сила_нп_джерело', 'блокує'} <= п.keys(), п
                    очік = реєстр.зн(д['правило'], д['сила'], д['суть'], [], д.get('чому', ''))
                    assert all(п[к] == з for к, з in очік.items()), (текст, п, очік)
                    знахідок += 1
                    правила[п['правило']] += 1
                    if д['сила'] != п['сила']:
                        зміни_сили[(п['правило'], д['сила'], п['сила'])] += 1
    стелі = []
    for текст, поле, правило, сила in [
        (формули[0], 'порушення', 'R-ONB-06', 'hard'),
        ('Для кольоротипу «літо» беріть приглушені відтінки', 'порушення', 'R-TYP-05', 'hard'),
        ('Рятуємо вас від перевантаження вибором', 'карантин', 'R-PSY-03/04', 'hint'),
        ('Красивое платье', 'порушення', нова.ЯРУС_УКРАЇНСЬКОЇ, 'hard')]:
        ключ = '__проба_мови_T3'
        assert ключ not in реєстр.REGISTRY
        реєстр.REGISTRY[ключ] = dict(t='T3', val=1, прав=[правило])
        try:
            п = next(п for п in нова._перевірити_обчислити(текст)[поле] if п['правило'] == правило)
            очік = реєстр.зн(правило, сила, 'контрольна знахідка', [], '')
            assert п['сила'] == очік['сила'] and п.get('стеля_тіру') == очік.get('стеля_тіру'), п
            стелі.append(dict(правило=правило, заявлено=сила, сила=п['сила'], стеля=п.get('стеля_тіру')))
        finally:
            del реєстр.REGISTRY[ключ]
    # Кеш повертає копію вкладених полів, зокрема нових полів конструктора.
    копія = нова.перевірити(формули[0])
    копія['порушення'][0]['збіги'].clear()
    assert нова.перевірити(формули[0])['порушення'][0]['збіги']
    звіт = dict(база=база, речей=len(речі), назв=len(назви), формул=len(формули),
        порівнянь=2 * (len(формули) + len(назви)), знахідок=знахідок,
        правила=dict(правила), зміни_сили=[dict(правило=п, до=д, після=з, кількість=к)
            for (п, д, з), к in зміни_сили.items()], стелі=стелі,
        рішення_видачі_суть_збіги_позиції_альтернативи='тотожні',
        пояснення='Початкове чому передано конструктору; його нота про правило поза корпусом додається за спільною політикою.',
        межа='Старий модуль із поточними залежностями; моделі не викликалися.')
    pathlib.Path(__file__).with_name('крок1_мова.json').write_text(
        json.dumps(звіт, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print('ФАКТ · речей', len(речі), 'назв', len(назви), 'знахідок', знахідок, 'стель', len(стелі))


if __name__ == '__main__':
    головна()
