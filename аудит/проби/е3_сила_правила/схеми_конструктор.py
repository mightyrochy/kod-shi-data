"""Порівнює всі п'ять емісій K-COL-03 із функціями бази й спільним конструктором.

Запуск із кореня: python аудит/проби/е3_сила_правила/схеми_конструктор.py <SHA> <JSON>.
Старі функції виконуються з поточними залежностями, не в окремому старому дереві.
"""
import ast
import copy
import json
import pathlib
import subprocess
import sys
from unittest.mock import patch

КОРІНЬ = pathlib.Path(__file__).resolve().parents[3]
sys.path.insert(0, str(КОРІНЬ / "джерела"))
import palette as П
import colorspace as К
import areas as А
import реєстр_правил as Р
import палітра_схеми as С


def випадки():
    """Входи п'яти емісій, особистого вибору й мовчання без вимірів."""
    def річ(ід, слот, колір, **дані):
        """Річ із виміряним кольором, без каталожних дефолтів."""
        return dict(id=ід, слот=слот, lab=К.hx(колір), **дані)
    бордо = річ("бордо", "сукня", "#6e2a2c", верх_см=140, низ_см=65)
    сірий = річ("сірий", "верх", "#8a8a88")
    хвоя = річ("хвоя", "верх", "#2f5e46", верх_см=140, низ_см=130)
    тони = П.СХЕМИ["приглушена_комплементарна"]["тон"](К.lch(бордо["lab"])[2])
    сім = [dict(роль=р, дуга=list(тони[р])) for р in ("домінанта", "секундант")]
    спец = dict(_сім_ї=сім, _схема="приглушена_комплементарна", _поверхні="великі")
    кат = {р["id"]: р for р in (бордо, сірий, хвоя)}
    пул = {"верх": [хвоя], "сукня": [бордо]}
    вих = []
    for межа in (True, False, None):
        вих.append(("відсутня сім'я, межа=" + str(межа), "обіцянка_великих",
                    ([бордо, сірий], спец, кат, пул), dict(межа_людини=межа)))
    вих.append(("брак асортименту", "обіцянка_великих", ([бордо, сірий], спец, кат, {}),
                dict(межа_людини=True)))
    тіло = dict(профіль=А.профіль_тіла(164, dict(плечі=112, груди=94, талія=74, стегна=100)))
    вих.append(("нерівні площі", "обіцянка_великих", ([бордо, хвоя], спец, кат, пул, тіло), {}))
    верх, низ = річ("верх", "верх", "#dadada"), річ("низ", "низ", "#343434")
    сумка = річ("сумка", "сумка", "#c8102e")
    акцент = dict(_схема="нейтрали+акцент", сумка=dict(роль="акцент", C=[30, 70]))
    вих.append(("немає акценту", "обіцянка_схеми", ([верх, низ], акцент), {}))
    вих.append(("два акценти", "обіцянка_схеми", ([бордо, хвоя, сумка], акцент, кат | {"сумка": сумка}), {}))
    тональна = {сл: dict(роль=р, L=[5, 95], C=[14, 34], дуга_тону=(0, 40))
                for сл, р in (("верх", "домінанта"), ("низ", "секундант"), ("сумка", "акцент"))}
    тональна["_схема"] = "тональна"
    вих.append(("тон лише на сумці", "обіцянка_схеми", ([верх, низ, сумка], тональна), {}))
    вих.append(("без виміру", "обіцянка_схеми", ([dict(id="невідомий", слот="верх")], акцент), {}))
    return вих


def старі_функції(sha):
    """Відновлює дві функції зі старої голови з незміненими залежностями."""
    текст = subprocess.check_output(["git", "show", sha + ":джерела/палітра_схеми.py"], cwd=КОРІНЬ).decode("utf-8")
    простір = dict(vars(С))
    for вузол in ast.parse(текст).body:
        if isinstance(вузол, ast.FunctionDef) and вузол.name in ("обіцянка_великих", "обіцянка_схеми"):
            exec(compile(ast.Module(body=[вузол], type_ignores=[]), "функція_бази", "exec"), простір)
    # Старий словник ваг потрібен тільки старій функції.
    for вузол in ast.parse(текст).body:
        if isinstance(вузол, ast.Assign) and any(isinstance(n, ast.Name) and n.id == "_СИЛА_НП_К03" for n in вузол.targets):
            exec(compile(ast.Module(body=[вузол], type_ignores=[]), "константа_бази", "exec"), простір)
    return простір


def головна():
    """Записує фактичні ДО/ПІСЛЯ та перевіряє стелі всіх емітентів."""
    sha, шлях = sys.argv[1:3]
    старі = старі_функції(sha)
    звіт = dict(база=sha, межа=__doc__, випадки=[], стелі=[], рядки_емісії=[])
    рядки = set()
    зн = Р.зн
    def записати(*args, **kwargs):
        """Фіксує справжні виклики конструктора без зміни їхнього результату."""
        рядки.add(sys._getframe(1).f_lineno)
        return зн(*args, **kwargs)
    for назва, ім, args, kwargs in випадки():
        до = старі[ім](*copy.deepcopy(args), **kwargs)
        with patch.object(Р, "зн", записати):
            після = getattr(С, ім)(*copy.deepcopy(args), **kwargs)
        assert len(до) == len(після), назва
        for д, п in zip(до, після):
            for поле in ("суть", "чому", "речі", "слот", "ярлик", "заяви", "ремонт_заяви", "частки", "площі_джерело", "що_зняло_б", "бік"):
                assert д.get(поле) == п.get(поле), (назва, поле, д.get(поле), п.get(поле))
            assert п["сила"] == "default" and п["регістр"] == "репліка" and п["блокує"] is False, п
            assert п["сила_нп"] == зн("K-COL-03", "default", п["суть"], п["речі"], п["чому"])["сила_нп"]
            assert {"для_стиліста", "сила_нп_джерело", "блокує"} <= п.keys(), п
        звіт["випадки"].append(dict(назва=назва, до=до, після=після))
    assert len(рядки) == 5, рядки
    # Контроль майбутньої T3-константи під правилом: число нейтральності незмінне.
    # Це тимчасова фікстура реєстру, а не зміна тіру чи прав продукту.
    for тір, сила in (("T1", "default"), ("T3", "soft")):
        запис = dict(Р.REGISTRY["neutral_C"], t=тір, прав=["K-COL-03"])
        with patch.dict(Р.REGISTRY, neutral_C=запис):
            for назва, ім, args, kwargs in випадки():
                for з in getattr(С, ім)(*copy.deepcopy(args), **kwargs):
                    assert з["сила"] == сила and з["регістр"] == "репліка" and not з["блокує"], з
                    звіт["стелі"].append(dict(випадок=назва, тір=тір, сила=з["сила"]))
    звіт["рядки_емісії"] = sorted(рядки)
    pathlib.Path(шлях).write_text(json.dumps(звіт, ensure_ascii=False, indent=2), encoding="utf-8")
    print("ФАКТ · емісій 5/5; випадків %d; перевірок стелі %d" % (len(звіт["випадки"]), len(звіт["стелі"])))


if __name__ == "__main__":
    головна()
