# -*- coding: utf-8 -*-
"""Е3-сила-правила, п.1а, частина 2: звірка дев'яти словників `суд_від_моделі.py`, переведених на `зн`.

Запуск із кореня репозиторію (каталог розпаковано: `чистка_каталогу.забезпечити_чистим`):
  python3 аудит/проби/е3_сила_правила/суд_звірка.py знімок <дерево> <вихід.json>
  python3 аудит/проби/е3_сила_правила/суд_звірка.py порівняти <ДО.json> <ПІСЛЯ.json> <звіт.json>

<дерево> — корінь робочого дерева (база — `git worktree add /tmp/база origin/main`). Знімок кличе продукт
того дерева без моделей:
  · канонічний дріт суду `bridge.виклик("від_моделі")` над складами з пулу `запити` повного каталогу:
    шість сцен `стенд_знімок.СЦЕНАРІЇ` × три схеми × схему обрала вона / не вона; склад — верх, низ,
    взуття, сумка (по 1–2 перші кандидати) плюс аксесуар акцентного слота, якщо пул його має; у половині
    складів `текст_моделі` з фольклорними числами (K-COL-07, R-ABC-11) — гілка фольклорних констант;
  · ті самі склади — прямо функціями суду до точки збору (`схема_образу`, `палітра_образу`,
    `бюджет_і_відлуння`, `акцент_образу`, `структура_образу`, `доповнення_судді`): канонічний дріт
    ріже вагу й відсіює частину знахідок, а звірка мусить бачити кожну емісію дев'яти місць;
  · синтетичні входи тих місць, яких каталог може не дати: K-PAL-03 обома гілками (нейтральна роль,
    поза дугою) × хто обрав схему (вона / модель / ранг коду / не питали), K-PAL-18 обома гілками,
    `доповнення_судді` над назвами речей (зони, принти, метал, блиск) і `структура_образу` під спекою.
Порівняння: за ключем — мультимножини знахідок без порядкового `ід`; змінені поля кожного правила ДО → ПІСЛЯ.
"""
import collections
import copy
import itertools
import json
import os
import sys

ФОЛЬКЛОР = ("Правило 60-30-10 дасть вам збалансований образ, а золотий перетин 1.618 "
            "тримає пропорції жакета.")
ПРАВИЛА_МІСЦЬ = None   # усі правила; змінені групуються за правилом


def _без_ід(з):
    return {к: в for к, в in з.items() if к != "ід"}


def _знімок(дерево, вихід):
    корінь = os.path.abspath(дерево)
    os.chdir(os.path.join(корінь, "джерела"))
    sys.path.insert(0, os.path.join(корінь, "джерела"))
    import warnings
    warnings.simplefilter("ignore")
    import bridge as Б
    import стенд_знімок as З
    import суд_від_моделі as СВ

    вх = json.load(open("стенд_вх.json", encoding="utf-8"))
    вих = {}

    def запис(ключ, знахідки):
        вих[ключ] = sorted(json.dumps(_без_ід(з), ensure_ascii=False, sort_keys=True, default=str)
                           for з in (знахідки or []) if isinstance(з, dict))

    # 1) синтетика: K-PAL-03 обома гілками × хто обрав схему
    червона = dict(id="с1", слот="сукня", назва="сукня червона", hex="#c0392b")
    сіра = dict(id="н1", слот="взуття", назва="туфлі сірі", hex="#8a8a8a")
    хто = {"вона": "her", "розмова": "conversation", "модель": "stylist", "ранг": "code_rank", "не_питали": None}
    for н, х in хто.items():
        сц = {} if х is None else dict(вибір_схеми=dict(обрала=dict(scheme=х)))
        for нд, сп in (("нейтраль", dict(роль="домінанта", дуга_тону="нейтраль")),
                       ("поза_дугою", dict(роль="домінанта", дуга_тону=[180, 240])),
                       ("у_дузі", dict(роль="домінанта", дуга_тону=[340, 40]))):
            запис("K-PAL-03|%s|%s" % (н, нд), СВ.схема_образу([червона, сіра], {"сукня": сп, "_схема": "тональна"},
                                                               {"с1": червона, "н1": сіра}, сц))

    # 2) синтетика: K-PAL-18 — акцент тьмяний, пул мав / не мав
    тьмяна = dict(id="а1", слот="сумка", назва="сумка бежева", hex="#b8a99a")
    гучна = dict(id="а2", слот="сумка", назва="сумка червона", hex="#d01c1f")
    спец = {"сумка": dict(роль="акцент", C=[40, 90]), "_схема": "нейтрали+акцент"}
    for нп, пул in (("мав", [гучна, тьмяна]), ("не_мав", [тьмяна])):
        запис("K-PAL-18|%s" % нп, СВ.акцент_образу([тьмяна], спец, {"сумка": пул},
                                                    {"а1": тьмяна, "а2": гучна}))

    # 3) синтетика: доповнення судді за назвою речі
    назви = [
        ("зони", [dict(id="в1", слот="верх", назва="топ без рукавів", рукав_рівень="без рукавів", виріз_тип="глибокий V"),
                  dict(id="н2", слот="низ", назва="шорти", тип="шорти", довжина_рівень="міні")], dict(пора="день")),
        ("принти", [dict(id="в2", слот="верх", назва="блуза в смужку"),
                    dict(id="н3", слот="низ", назва="спідниця в квітковий принт")], {}),
        ("метал_тепла", [dict(id="п1", слот="прикраси", назва="срібні сережки")], {}),
        ("метал_холодна", [dict(id="п2", слот="прикраси", назва="золоті сережки")], {}),
        ("блиск", [dict(id="в3", слот="верх", назва="топ з паєтками")], dict(пора="день")),
    ]
    for нз, речі, сц in назви:
        for драп in (dict(метал="золото"), dict(метал="срібло"), None):
            запис("доповнення|%s|%s" % (нз, (драп or {}).get("метал")), СВ.доповнення_судді(речі, сц, драп))

    # 4) синтетика: третя річ і лічба під спекою й сукнею-фокусом (Н-2 — репліка `_бл_або_мʼяко`)
    for нс, сц in (("спека", dict(смуга_погоди="hot")), ("звичайно", dict(смуга_погоди="mild"))):
        for нр, речі in (("дві", [dict(id="в4", слот="верх", назва="футболка", тип="футболка"),
                                  dict(id="н4", слот="низ", назва="джинси", тип="джинси")]),
                         ("сукня", [dict(id="с2", слот="сукня", назва="сукня з принтом", тип="сукня", принт="квітковий"),
                                    dict(id="в5", слот="взуття", назва="сандалі", тип="сандалі")])):
            пари, мʼякі = СВ.структура_образу_заяви(речі, None, сц)
            запис("структура|%s|%s" % (нс, нр), мʼякі + [dict(блокер=т, заява=з) for т, з in пари])

    # 5) каталог: канонічний дріт і функції суду над складами з пулу
    кількість = collections.Counter()
    for сцена, сценарій in (З.СЦЕНАРІЇ.items() if not os.environ.get("ZVIRKA_BEZ_KATALOHU") else ()):
        for схема in ("нейтрали+акцент", "тональна", "тріада"):
            for вона in (True, False):
                запит = dict(вх, сценарій=сценарій, схема=схема, **({"схему_обрала_вона": True} if вона else {}))
                пакет = json.loads(Б.виклик("запити", json.dumps(запит, ensure_ascii=False)))
                if пакет.get("помилка"):
                    вих["помилка|%s|%s|%s" % (сцена, схема, вона)] = [str(пакет.get("помилка"))[:300]]
                    continue
                кат = Б.каталог_останнього_пакета()
                за_ід = {р["id"]: р for р in кат}
                пул = пакет.get("кандидати") or {}
                слоти = [пул.get(с, [])[:2 if с in ("верх", "сумка") else 1] for с in ("верх", "низ", "взуття", "сумка")]
                акс = next((пул[с][:1] for с in ("прикраси", "шарф", "сережки", "пояс") if пул.get(с)), [])
                for н, склад in enumerate(itertools.product(*[с for с in слоти if с])):
                    склад = list(склад) + (акс if н % 2 else [])
                    ід = [р["id"] for р in склад]
                    дані = dict(запит, ід=ід, **({"текст_моделі": ФОЛЬКЛОР} if н % 2 == 0 else {}))
                    ключ = "%s|%s|%s|%s" % (сцена, схема, вона, ",".join(ід))
                    відп = json.loads(Б.виклик("від_моделі", json.dumps(дані, ensure_ascii=False)))
                    if відп.get("помилка"):
                        вих["дріт|" + ключ] = ["помилка: %s" % str(відп.get("помилка"))[:300]]
                        continue
                    о = (відп.get("вердикт") or {}).get("образи") or [{}]
                    запис("дріт|" + ключ, copy.deepcopy(о[0].get("знахідки") or []))
                    кількість["складів"] += 1
                    # функції суду до точки збору — ті самі речі, повні з каталогу
                    речі = [dict(за_ід.get(р["id"]) or р) for р in склад]
                    спец_слоти = (пакет.get("спец") or {}).get("слоти") or {}
                    try:
                        сц = dict(сценарій, вибір_схеми=dict(обрала=dict(scheme="her" if вона else "code_rank")))
                        запис("функції|" + ключ, СВ.схема_образу(речі, спец_слоти, за_ід, сц)
                              + СВ.акцент_образу(речі, спец_слоти, {к: [за_ід.get(x["id"]) or x for x in в]
                                                                   for к, в in пул.items()}, за_ід)
                              + СВ.доповнення_судді(речі, сценарій, None))
                    except Exception as e:
                        вих["функції|" + ключ] = ["виняток: %s: %s" % (type(e).__name__, str(e)[:200])]
    вих["_кількість"] = [json.dumps(dict(кількість), ensure_ascii=False)]
    json.dump(вих, open(вихід, "w", encoding="utf-8"), ensure_ascii=False, indent=0, sort_keys=True)


def _порівняти(до_ш, після_ш, звіт_ш):
    до, після = json.load(open(до_ш, encoding="utf-8")), json.load(open(після_ш, encoding="utf-8"))
    звіт = dict(ключів=len(до), тотожних=0, змінених=0, лише_до=sorted(set(до) - set(після)),
                лише_після=sorted(set(після) - set(до)), за_правилом={}, приклади={}, кількість=до.get("_кількість"))
    поля = collections.defaultdict(collections.Counter)
    for ключ in sorted(set(до) & set(після)):
        if до[ключ] == після[ключ]:
            звіт["тотожних"] += 1
            continue
        звіт["змінених"] += 1
        с = collections.Counter(до[ключ]); н = collections.Counter(після[ключ])
        старі = [json.loads(x) if x.startswith("{") else {"текст": x} for x in (с - н).elements()]
        нові = [json.loads(x) if x.startswith("{") else {"текст": x} for x in (н - с).elements()]
        # пара за правилом і суттю (суть від сили не залежить)
        for ст in старі:
            пара = next((нв for нв in нові if нв.get("правило") == ст.get("правило")
                         and str(нв.get("суть", "")).split(" [")[0] == str(ст.get("суть", "")).split(" [")[0]), None)
            п = ст.get("правило", "?")
            if пара is None:
                поля[п]["зникла"] += 1
                звіт["приклади"].setdefault("%s|зникла" % п, dict(ключ=ключ, до=ст))
                continue
            нові.remove(пара)
            for к in sorted(set(ст) | set(пара)):
                if ст.get(к) != пара.get(к):
                    тип = "%s: %s → %s" % (к, json.dumps(ст.get(к), ensure_ascii=False)[:60],
                                          json.dumps(пара.get(к), ensure_ascii=False)[:60]) \
                        if к in ("сила", "регістр", "блокує", "впевненість", "сила_нп", "сила_нп_джерело",
                                 "стеля_тіру", "стеля_корпусу", "гейт_знято") else к
                    поля[п][тип] += 1
            звіт["приклади"].setdefault(п, dict(ключ=ключ, до=ст, після=пара))
        for нв in нові:
            п = нв.get("правило", "?")
            поля[п]["зʼявилась"] += 1
            звіт["приклади"].setdefault("%s|зʼявилась" % п, dict(ключ=ключ, після=нв))
    звіт["за_правилом"] = {п: dict(в) for п, в in sorted(поля.items())}
    json.dump(звіт, open(звіт_ш, "w", encoding="utf-8"), ensure_ascii=False, indent=1, sort_keys=True)
    print("ключів %d · тотожні %d · змінені %d · лише ДО %d · лише ПІСЛЯ %d" % (
        звіт["ключів"], звіт["тотожних"], звіт["змінених"], len(звіт["лише_до"]), len(звіт["лише_після"])))
    for п, в in звіт["за_правилом"].items():
        print(" ", п, dict(в))


if __name__ == "__main__":
    if sys.argv[1] == "знімок":
        _знімок(sys.argv[2], os.path.abspath(sys.argv[3]))
    else:
        _порівняти(*sys.argv[2:5])
