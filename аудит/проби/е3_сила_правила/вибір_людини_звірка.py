# -*- coding: utf-8 -*-
"""Е3-сила-правила, п.1б–в, крок 2: звірка трьох останніх місць, переведених на `перезважити`.

Запуск із кореня репозиторію:
  python3 аудит/проби/е3_сила_правила/вибір_людини_звірка.py <дерево> > вихід.json   — знімок одного дерева
  python3 аудит/проби/е3_сила_правила/перезважити_звірка.py --порівняти ДО.json ПІСЛЯ.json

<дерево> — корінь робочого дерева (база — `git worktree add /tmp/база origin/main`). Знімок кличе ті
самі функції продукту на синтетичних знахідках, без моделей і каталогу:
  · `зн` — та сама сітка, що в `перезважити_звірка.py` (правила політики × сили × реєстри модулів):
    конструктор мусить лишитися тотожним;
  · `колір_світлота.гейт_контрасту` — K-CLR-02 кожної сили з шумною й тихою віссю контрасту, з
    ремонтом і без, з приміткою й без, і як задум мисматчу;
  · `річ_з_фото.без_замків` і `повнота_образу._суд_складу` — кожна знахідка-гейт, яку дає `зн`
    (правила політики × hard/strong × реєстри), лише про її річ з фото, про її річ і чужу, про
    чужу; плюс репліка й питання про її річ.
Порівняння — `перезважити_звірка.py --порівняти`: «тотожно» чи ключі, що змінились, ДО → ПІСЛЯ.
"""
import json
import os
import sys


def _знімок(дерево):
    sys.path.insert(0, os.path.join(os.path.abspath(дерево), "джерела"))
    os.chdir(os.path.join(os.path.abspath(дерево), "джерела"))
    import warnings
    warnings.simplefilter("ignore")
    import реєстр_сила as RS
    import реєстр_політика as RP
    import аксесуари_реєстр as AREG
    import fit as FIT
    import верхнє_реєстр as VR
    import колір_світлота as KS
    import річ_з_фото as RF
    import повнота_образу as PO

    СИЛИ = ("hard", "strong", "default", "soft", "hint")
    вих = {}

    def з(п, с, речі=("річ а", "річ б"), **kw):
        return RS.зн(п, с, "суть правила %s — хвіст" % п, list(речі), "чому %s" % п, **kw)

    правила = sorted(set(RP.ПОЛІТИКА_РЕГІСТРУ) | {"K-KOH-05", "K-COL-06-T", "K-CLR-02", "K-EYE-02",
                                                   "K-BOD-02", "K-INT-04", "K-KOH-02", "K-FIT-04", "K-WEA-05",
                                                   "K-PC-08", "K-HAT-01"})
    реєстри = {"ядро": None, "аксесуари": AREG.РЕЄСТР, "fit": FIT.РЕЄСТР, "верхнє": VR.РЕЄСТР}

    # 1) конструктор: тотожність `зн`
    for п in правила:
        for с in СИЛИ + ("питання", "утримано"):
            for нр, reg in реєстри.items():
                вих["зн|%s|%s|%s" % (п, с, нр)] = з(п, с, ремонт=["ремонт %s" % п], reg=reg)
            вих["зн|%s|%s|поріг" % (п, с)] = з(п, с, ремонт="Ремонт рядком", поріг=2.0, вимір=3.1)

    # 2) гейт осі контрасту: K-CLR-02 на крок нижче
    шумна = dict(надійність_контрасту=dict(регіональний_шум=4.0, надійність=0.1, чому="шум профілю"))
    тиха = dict(надійність_контрасту=dict(регіональний_шум=None, надійність=1.0, чому="—"))
    мисматч = dict(гілка="мисматч", базова="контраст", власний=40.0, підставлений=60.0,
                   рівень_власний="середній", рівень_образу="високий", чому="обрала мисматч")
    for с in СИЛИ + ("питання",):
        for нп, особа in (("шум", шумна), ("тихо", тиха)):
            for вид, kw in (("ремонт", dict(ремонт=["інший верх"], поріг=10.0, вимір=25.0)),
                            ("без_ремонту", {}), ("примітка", dict(примітка="своя примітка", ремонт="Інший верх"))):
                вих["гейт_контрасту|%s|%s|%s" % (с, нп, вид)] = KS.гейт_контрасту(з("K-CLR-02", с, **kw), особа)
            вих["гейт_контрасту|%s|%s|задум" % (с, нп)] = KS.гейт_контрасту(
                KS._задум_мисматчу(з("K-CLR-02", с, ремонт=["інший верх"]), мисматч, 60.0, 5.0), особа)

    # 3) без замків: гейт над її річчю з фото → репліка
    її = dict(id="її-ф1", назва="її сукня")
    чужа = dict(id="к1", назва="жакет")
    гейти = []
    for п in правила:
        for с in ("hard", "strong"):
            for нр, reg in реєстри.items():
                z = з(п, с, ремонт=["замінити річ"], reg=reg, поріг=2.0, вимір=3.0)
                if z.get("регістр") == "гейт":
                    гейти.append(("%s|%s|%s" % (п, с, нр), п, с, reg))
    вих["гейтів_у_сітці"] = len(гейти)
    for ключ, п, с, reg in гейти:
        for нр, речі in (("її", ["її-ф1"]), ("її_назвою", ["її сукня"]), ("її_й_чужа", ["її-ф1", "к1"]),
                         ("чужа", ["к1"]), ("образ", [])):
            z = з(п, с, речі=речі, ремонт=["замінити річ"], reg=reg, поріг=2.0, вимір=3.0)
            блокує, знахідки = RF.без_замків([z], [z], [її, чужа])
            вих["без_замків|%s|%s" % (ключ, нр)] = dict(блокує=блокує, знахідки=знахідки)
    for с in ("soft", "питання"):
        z = з("K-PAL-03", с, речі=["її-ф1"], ремонт=["замінити річ"])
        вих["без_замків|K-PAL-03|%s|не_гейт" % с] = RF.без_замків([], [z], [її, чужа])[1]

    # 4) суд складу: та сама межа на закріпленій речі в ремонті гейтів
    словник = {"її-ф1": dict(назва="її сукня", власна=True), "к1": dict(назва="жакет")}
    ід = ["її-ф1", "к1"]
    for ключ, п, с, reg in гейти:
        for нр, речі in (("її", ["її-ф1"]), ("її_й_чужа", ["її-ф1", "к1"]), ("чужа", ["к1"])):
            z = з(п, с, речі=речі, ремонт=["замінити річ"], reg=reg, поріг=2.0, вимір=3.0)
            вих["суд_складу|%s|%s" % (ключ, нр)] = PO._суд_складу(dict(знахідки=[z]), ід, [], ["її-ф1"],
                                                                   словник, {})
        z = з(п, с, речі=["її-ф1"], ремонт=["замінити річ"], reg=reg)
        вих["суд_складу|%s|свідомий" % ключ] = PO._суд_складу(
            dict(знахідки=[z]), ід, [(п, {"її-ф1"}, "навмисно")], ["її-ф1"], словник, {})
    return вих


if __name__ == "__main__":
    print(json.dumps(_знімок(sys.argv[1]), ensure_ascii=False, indent=None, sort_keys=True, default=str))
