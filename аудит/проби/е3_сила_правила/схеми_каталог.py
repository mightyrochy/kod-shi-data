"""Порівнює суд вибірки складів повного каталогу зі старими й новими емітентами K-COL-03.

python аудит/проби/е3_сила_правила/схеми_каталог.py <SHA> <JSON>
Старі функції виконуються з поточними залежностями; це не окреме старе дерево.
"""
import copy
import itertools
import json
import os
import pathlib
import sys
from unittest.mock import patch
from схеми_конструктор import старі_функції, КОРІНЬ, С, П

os.chdir(КОРІНЬ / "джерела")
import bridge as Б
import стенд_знімок as З


def головна():
    """Звіряє фінальний перелік знахідок, зберігає різниці й дві речі для огляду."""
    sha, шлях = sys.argv[1:3]
    вихід = (КОРІНЬ / шлях).resolve()
    старі = старі_функції(sha)
    вхід = json.loads(pathlib.Path("стенд_вх.json").read_text(encoding="utf-8"))
    звіт = dict(база=sha, межа=__doc__, склади=[], речі=[], сцен=0, схем=3)
    def зберегти():
        """Зберігає вже виміряні факти перед наступним складом."""
        вихід.write_text(json.dumps(звіт, ensure_ascii=False, indent=2), encoding="utf-8")
    def суд(запит):
        """Канонічний фінальний перелік, без повторного підрахунку вкладеної діагностики."""
        відповідь = json.loads(Б.виклик("від_моделі", json.dumps(запит, ensure_ascii=False)))
        assert not відповідь.get("помилка"), відповідь
        return відповідь["вердикт"]["образи"][0].get("знахідки") or []
    for сцена, сценарій in З.СЦЕНАРІЇ.items():
        звіт["сцен"] += 1
        for схема in ("нейтрали+акцент", "тональна", "тріада"):
            запит = dict(вхід, сценарій=сценарій, схема=схема, схему_обрала_вона=True)
            пакет = json.loads(Б.виклик("запити", json.dumps(запит, ensure_ascii=False)))
            assert not пакет.get("помилка"), пакет
            кат = Б.каталог_останнього_пакета()
            звіт["каталог_речей"] = len(кат)
            пул = пакет.get("кандидати") or {}
            слоти = [пул.get(с, [])[:2 if с in ("верх", "сумка") else 1] for с in ("верх", "низ", "взуття", "сумка")]
            for склад in itertools.product(*[с for с in слоти if с]):
                ід = [р["id"] for р in склад]
                дані = dict(запит, ід=ід)
                with patch.object(С, "обіцянка_схеми", старі["обіцянка_схеми"]), patch.object(С, "обіцянка_великих", старі["обіцянка_великих"]), patch.object(П, "обіцянка_великих", старі["обіцянка_великих"]):
                    до = copy.deepcopy(суд(дані))
                після = copy.deepcopy(суд(дані))
                інші = lambda зн: sorted((json.dumps(з, ensure_ascii=False, sort_keys=True) for з in зн if з.get("правило") != "K-COL-03"))
                assert інші(до) == інші(після), (сцена, схема, ід, "змінено інші правила")
                к03 = lambda зн: [з for з in зн if з.get("правило") == "K-COL-03"]
                д, п = к03(до), к03(після)
                assert len(д) == len(п), (сцена, схема, ід, д, п)
                for старе, нове in zip(д, п):
                    assert all(старе.get(к) == нове.get(к) for к in ("суть", "речі", "заяви", "ремонт_заяви"))
                    assert нове["сила"] in ("default", "soft") and нове["регістр"] == "репліка" and not нове["блокує"]
                звіт["склади"].append(dict(сцена=сцена, схема=схема, ід=ід, до=д, після=п, інших=len(інші(після))))
                if not звіт["речі"]:
                    звіт["речі"] = [{к: р.get(к) for к in ("id", "назва", "фото", "url", "слот", "lab")} for р in кат if р["id"] in ід]
                зберегти()
        print("ФАКТ ·", сцена, "складів", len(звіт["склади"]), flush=True)
    print("ФАКТ · каталог", звіт["каталог_речей"], "складів", len(звіт["склади"]), "інші правила тотожні", flush=True)


if __name__ == "__main__":
    головна()
