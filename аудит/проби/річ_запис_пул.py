"""Шкода в пулі показу (доповнення спроби 2 наряду Річ-запис-речі-мірило-каталогу).

Запуск із кореня: python3 -X utf8 аудит/проби/річ_запис_пул.py [--вибірки | --частки]
Без мережі, з читачі.jsonl.gz протоколу п.1. Пул показу — речі, які продукт може показати жінці:
готовий запис має слот для каналу «жіноче» (після відсічення каналом і не-одягом) і є показний кадр.
--вибірки пише пул_вибірки.json (зерно 11658): 80 розбіжних і 80 згідних читачів у пулі; 90 речей без типу.
--частки читає рішення очима з очі_пул.json і рахує частки з інтервалом Вілсона (95 %).
"""
import collections
import gzip
import json
import math
from pathlib import Path
import random
import sys

ТЕКА = Path(__file__).resolve().parent / 'річ_запис_каталог_2026_10_30'
ЗЕРНО = 11658


def читачі():
    """Прочитати протокол п.1."""
    return [json.loads(р) for р in gzip.decompress((ТЕКА / 'читачі.jsonl.gz').read_bytes()).decode().splitlines()]


def у_пулі(р):
    """Слот готового запису для жіночого каналу є і є кадр."""
    return bool(р['читачі']['читання_запису']['слот']) and bool(р['кадр'])


def вілсон(к, н):
    """Інтервал Вілсона 95 % для частки к з н."""
    if not н:
        return (0.0, 0.0)
    п, z = к / н, 1.96
    ц = (п + z * z / (2 * н)) / (1 + z * z / н)
    д = z * math.sqrt(п * (1 - п) / н + z * z / (4 * н * н)) / (1 + z * z / н)
    return (ц - д, ц + д)


def вибірки():
    """Скласти сталі вибірки для огляду очима."""
    всі = sorted(читачі(), key=lambda р: р['id'])
    пул = [р for р in всі if у_пулі(р)]
    розбіжні = [р for р in пул if р['різні']]
    згідні = [р for р in пул if not р['різні']]
    без_типу = [р for р in всі if not р['читачі']['запис_входу']['тип']]
    г = random.Random(ЗЕРНО)
    вибір = dict(
        розбіжні=g_sample(г, розбіжні, 80), згідні=g_sample(г, згідні, 80), без_типу=g_sample(г, без_типу, 90))
    розмір = dict(усього=len(всі), пул=len(пул), розбіжні=len(розбіжні), згідні=len(згідні), без_типу=len(без_типу),
        без_типу_у_пулі=sum(у_пулі(р) for р in без_типу))
    вивід = dict(розмір=розмір, зерно=ЗЕРНО)
    for ключ, ряди in вибір.items():
        вивід[ключ] = [dict(id=р['id'], назва=р['назва'], розділ=р['категорія_магазину'], категорія=р['категорія'],
            тип=р['читачі']['запис_входу']['тип'], слот=р['читачі']['запис_входу']['слот'],
            читачі={к: v for к, v in р['читачі'].items() if v and к in ('вид_офера', 'жниварка_повтор', 'кадр', 'розбір_коду')},
            кадр=р['кадр']) for р in ряди]
    (ТЕКА / 'пул_вибірки.json').write_text(json.dumps(вивід, ensure_ascii=False, sort_keys=True, indent=1) + '\n', encoding='utf-8')
    print(розмір)


def g_sample(г, ряди, к):
    """Вибрати к рядків у сталому порядку."""
    return sorted(г.sample(ряди, к), key=lambda р: р['id'])


def частки():
    """Звести рішення очима в частки пулу."""
    в = json.loads((ТЕКА / 'пул_вибірки.json').read_text(encoding='utf-8'))
    очі = json.loads((ТЕКА / 'очі_пул.json').read_text(encoding='utf-8'))
    р = в['розмір']
    вивід = dict(розмір=р)
    for страта in ('розбіжні', 'згідні'):
        ряди = [очі[страта + ':' + x['id']] for x in в[страта]]
        н = len(ряди)
        хибних_слот = sum(not о['слот_ок'] for о in ряди)
        хибних_тип = sum(not о['тип_ок'] for о in ряди)
        хибних = sum((not о['слот_ок']) or (not о['тип_ок']) for о in ряди)
        вивід[страта] = dict(н=н, хибний_слот=хибних_слот, хибний_тип=хибних_тип, хибний_слот_або_тип=хибних,
            не_одяг=sum(о.get('не_одяг', False) for о in ряди),
            інтервал_слот_або_тип=[round(x, 3) for x in вілсон(хибних, н)])
    пул = р['пул']
    зважено = sum(р[с] * вивід[с]['хибний_слот_або_тип'] / вивід[с]['н'] for с in ('розбіжні', 'згідні')) / пул
    вивід['пул_хибних_слот_або_тип_оцінка'] = round(зважено, 4)
    без = [очі['без_типу:' + x['id']] for x in в['без_типу']]
    одяг = sum(o['одяг'] for o in без)
    втрачено = sum(o['одяг'] and not o['слот_є'] for o in без)
    у_пулі_без_типу = sum(o['одяг'] and o['слот_є'] for o in без)
    вивід['без_типу'] = dict(н=len(без), одяг=одяг, інтервал=[round(x, 3) for x in вілсон(одяг, len(без))],
        одягу_оцінка=round(р['без_типу'] * одяг / len(без)),
        одяг_без_слота_поза_пулом=втрачено, інтервал_втрат=[round(x, 3) for x in вілсон(втрачено, len(без))],
        втрат_оцінка=round(р['без_типу'] * втрачено / len(без)),
        одяг_зі_слотом_у_пулі_без_типу=у_пулі_без_типу)
    вивід['втрати_частка_пулу_з_втратами'] = round(вивід['без_типу']['втрат_оцінка'] / (пул + вивід['без_типу']['втрат_оцінка']), 4)
    (ТЕКА / 'пул_частки.json').write_text(json.dumps(вивід, ensure_ascii=False, sort_keys=True, indent=1) + '\n', encoding='utf-8')
    print(json.dumps(вивід, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    {'--вибірки': вибірки, '--частки': частки}[sys.argv[1] if len(sys.argv) > 1 else '--вибірки']()
