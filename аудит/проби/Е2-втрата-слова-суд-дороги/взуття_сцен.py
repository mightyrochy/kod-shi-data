"""МІРИЛО НАРЯДУ `Е2-втрата-слова-суд-дороги` (ДО на записах): взуття в образах чотирьох сцен «зима, пішки».

Сцени: с8 четвертого живого «як людина» (два проходи, `verdykty-*.json`) і нічні Е1-20261115 ж3_зима, ж8_зима,
ж8_ділова_мороз (`вердикти.txt`). Для кожного образу з речами каталогу (руки 1–2; руки 3–4 каталогу не мають) —
пара взуття, її висота каблука й підошва з картки крамниці (`фід_взуття.взуттєві_атрибути`, той самий читач, що в
продукті), діагноз суду K-SHO-16 «без входу» і знахідки K-SHO-16 / K-END-01 у знахідках коду (живий 4; нічний їх не пише).
Шпилька — слово «шпильк» у категорії, назві чи описі картки (`фід_взуття.З_КАБЛУКОМ`); гладка підошва — основа
«гладк» чи «шкіряна підошва» (`фід_взуття.ПІДОШВИ`).

Запуск з кореня репозиторію: `python3 аудит/проби/Е2-втрата-слова-суд-дороги/взуття_сцен.py`.
Останній рядок — `образів: N · зі шпилькою чи гладкою підошвою: M · високий каблук ≥ 6 см: K · діагноз «без входу»: D`."""
import glob, gzip, json, os, re, shutil, sys, tempfile
КОРІНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
sys.path.insert(0, os.path.join(КОРІНЬ, 'джерела'))
os.chdir(os.path.join(КОРІНЬ, 'джерела'))
import фід_розбір as Р, фід_взуття as В, фід_слот as С

НІЧНИЙ = os.path.join(КОРІНЬ, 'аудит', 'проби', 'Е1-нічний-живий-20261115')
ЖИВИЙ = os.path.join(КОРІНЬ, 'аудит', 'проби', 'живий-як-людина-4', 'с8_мінус_десять_сніг')


def вердикти():
    for ф in sorted(glob.glob(os.path.join(ЖИВИЙ, 'verdykty-*.json'))):
        for н, п in enumerate(json.load(open(ф, encoding='utf-8'))['прогони'], 1):
            діагноз = json.dumps(п, ensure_ascii=False)
            for в in п['вердикти']:
                yield 'с8 живий 4 · прохід %d' % н, в, діагноз
    for с in ('ж3_зима', 'ж8_зима', 'ж8_ділова_мороз'):
        т = open(os.path.join(НІЧНИЙ, с, 'вердикти.txt'), encoding='utf-8').read()
        for р in т.splitlines():
            р = р.strip().rstrip(',')
            if р.startswith('{"рука"'):
                yield с + ' нічний', json.JSONDecoder().raw_decode(р)[0], т


def каталог():
    тека = tempfile.mkdtemp()
    шлях = os.path.join(тека, 'кат.xml')
    with gzip.open(os.path.join(КОРІНЬ, 'каталог_повний.xml.gz'), 'rb') as f, open(шлях, 'wb') as g:
        shutil.copyfileobj(f, g)
    оф = {o['id']: o for o in Р.офери_фіду(шлях)}
    shutil.rmtree(тека)
    return оф


оф = каталог()
образів = шпилька_гладка = високий = без_входу = 0
for сцена, в, діагноз in вердикти():
    ід = [і for і in (в.get('склад') or '').split('+') if і.startswith('ж')]
    if not ід:
        continue
    взуття = [(і, оф[і]) for і in ід if і in оф and С.слоти(оф[і])['слот'] == 'взуття']
    образів += 1
    нема = bool(re.search(r'"K-SHO-16":\s*"сценарій\.тривалість_год\|поверхня: none"', діагноз))
    без_входу += нема
    знахідки = [(з.get('правило'), з.get('сила'), з.get('суть')) for з in (в.get('знахідки_коду') or [])
                if з.get('правило') in ('K-SHO-16', 'K-END-01')]
    рядки = []
    позначка = False
    for і, o in взуття:
        а = В.взуттєві_атрибути(o)
        текст = ' '.join(str(o.get(к) or '') for к in ('категорія', 'назва', 'опис')).lower()
        шп = 'шпильк' in текст or 'шпильц' in текст
        гл = а.get('підошва') in ('гладк', 'шкіряна підошва')
        позначка |= шп or гл
        високий += (а.get('каблук_см') or 0) >= 6
        рядки.append('%s «%s» тип=%s каблук=%s см=%s підошва=%s%s%s' % (
            і, o.get('назва'), В.тип_речі(o), а.get('каблук'), а.get('каблук_см'), а.get('підошва'),
            ' · ШПИЛЬКА' if шп else '', ' · ГЛАДКА ПІДОШВА' if гл else ''))
    шпилька_гладка += позначка
    print('%s · рука %s · позиція %s · K-SHO-16 без входу: %s · знахідки K-SHO-16/K-END-01: %s' % (
        сцена, в.get('рука'), в.get('позиція'), 'так' if нема else 'ні', знахідки or '—'))
    for р in рядки or ['взуття в образі нема']:
        print('    ' + р)
print('образів: %d · зі шпилькою чи гладкою підошвою: %d · високий каблук ≥ 6 см: %d · діагноз «без входу»: %d'
      % (образів, шпилька_гладка, високий, без_входу))

# ── ПІСЛЯ (код гілки на тих самих парах): суд K-SHO-16 зі сценарієм з її слів ─────────────────────────────────
# Записи поля дороги не несуть (схема його не мала), тривалості й поверхні — теж (діагноз ДО «none» в усіх).
# Сценарій — те, що вона сказала в усіх чотирьох сценах: «пішки 20 хвилин», «сніг»; тривалість події й поверхню вона
# не називала. Чи запише модель `walk_min` 20 — питання рядків `ЖИВИЙ ПІСЛЯ`, не цієї проби.
import аксесуари_носіння as АН
if hasattr(АН, 'бракує_входу'):
    СЦЕНА = dict(тривалість_год=None, поверхня=None, дорога_пішки_хв=20, опади='сніг')
    без_входу = із_силою = 0
    for сцена, в, _ in вердикти():
        ід = [і for і in (в.get('склад') or '').split('+') if і.startswith('ж')]
        речі = [dict(оф[і], id=і, слот='взуття', **В.взуттєві_атрибути(оф[і])) for і in ід
                if і in оф and С.слоти(оф[і])['слот'] == 'взуття']
        if not ід:
            continue
        без_входу += АН.бракує_входу(СЦЕНА['тривалість_год'], СЦЕНА['поверхня'], СЦЕНА['дорога_пішки_хв'])
        зн = АН.вартість_носіння(речі, **СЦЕНА)
        sho = [(з.get('правило'), з.get('сила'), (з.get('суть') or '')[:90]) for з in зн
               if з.get('правило') in ('K-SHO-16', 'K-END-01')]
        із_силою += any(з[1] in ('strong', 'soft', 'hint') for з in sho)
        print('ПІСЛЯ %s · рука %s · %s' % (сцена, в.get('рука'), sho or 'K-SHO-16 мовчить: каблука нема чи висота невідома'))
    print('ПІСЛЯ · сцена %s · діагноз «без входу»: %d · образів зі знахідкою K-SHO-16 із силою: %d'
          % (СЦЕНА, без_входу, із_силою))
    # Контроль: та сама сцена на парі каталогу з найвищим каблуком у сантиметрах — правило говорить, коли є що судити.
    пари = [(і, o) for і, o in оф.items() if С.слоти(o)['слот'] == 'взуття']
    і, o = max(пари, key=lambda п: В.взуттєві_атрибути(п[1]).get('каблук_см') or 0)
    пара = dict(o, id=і, слот='взуття', **В.взуттєві_атрибути(o))
    for сц in (СЦЕНА, dict(СЦЕНА, дорога_пішки_хв=None)):
        зн = [з for з in АН.вартість_носіння([пара], **сц) if з.get('правило') in ('K-SHO-16', 'K-END-01')]
        print('КОНТРОЛЬ %s «%s» %s см · дорога %s хв → %s' % (і, (o.get('назва') or '')[:40], пара.get('каблук_см'),
              сц['дорога_пішки_хв'], [(з['правило'], з['сила'], round(з.get('сила_нп') or 0, 2),
                                      (з.get('суть') or '')[:110]) for з in зн]))
