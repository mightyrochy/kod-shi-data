#!/usr/bin/env python3
"""Проба П12: «СЛОВО ВЛАСНИКА», звернене до відправника, `.claude/хуки/листи_менеджерові.py` повертає раз.

Запуск: python3 аудит/проби/хук_слово_до_відправника.py [шлях_до_хука]   (без аргументу — хук з робочого дерева).
Тексти штучні; справжні випадки 26.10–06.11 — `аудит/проби/хук_точки_дії_справжні.py`. Мірило: відповідь на рядок
відправника в лапках, питання й «ти» — повертається з нагадуванням; той самий лист удруге — відходить; слово про продукт
(без ознак) — відходить; слово, вкладене в лист без шапки, — повертається; лист не менеджерові — відходить; файл
відбитків не пишеться — лист відходить з попередженням.
"""
import json
import os
import subprocess
import sys
import tempfile

КОРІНЬ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
ХУК = sys.argv[1] if len(sys.argv) > 1 else os.path.join(КОРІНЬ, ".claude", "хуки", "листи_менеджерові.py")
МЕНЕДЖЕР, ДИСПЕТЧЕР = "session_MGR1", "session_DSP1"
СТАН = f"| роль | сесія |\n|---|---|\n| диспетчер | {ДИСПЕТЧЕР} |\n| менеджер | {МЕНЕДЖЕР} |\n"
СЛОВА = [
    ("2026-11-06T09:10:00Z", '"Чекаю на вільний слот" - чому чекаєш? Роби на іншій моделі.'),
    ("2026-11-06T09:20:00Z", "Ти знову не відповів мені сам."),
    ("2026-11-06T09:30:00Z", "Стилістка має пропонувати теплі тканини взимку."),
    ("2026-11-06T09:40:00Z", "Скільки коштує один прогін на ноутбуці?"),
]


def запуск(т, кому, текст, повтор):
    with open(os.path.join(т, "транскрипт.jsonl"), "w", encoding="utf-8") as ф:
        for коли, слово in СЛОВА:
            ф.write(json.dumps({"type": "user", "timestamp": коли, "origin": {"kind": "human"},
                                "message": {"role": "user", "content": слово}}, ensure_ascii=False) + "\n")
    вхід = {"tool_name": "mcp__claude-code-remote__send_message", "tool_input": {"session_id": кому, "message": текст},
            "transcript_path": os.path.join(т, "транскрипт.jsonl")}
    env = dict(os.environ, CLAUDE_PROJECT_DIR=т, ЛИСТИ_СТАН_ФАЙЛ=os.path.join(т, "зведення"), ЛИСТИ_ПОВТОР_ФАЙЛ=повтор,
               ЛИСТИ_ЗАРАЗ="2026-11-06T10:00:00Z", CLAUDE_CODE_REMOTE_SDK_URL="https://x/sessions/cse_DSP1")
    р = subprocess.run([sys.executable, ХУК], input=json.dumps(вхід, ensure_ascii=False), capture_output=True,
                       text=True, encoding="utf-8", env=env)
    причина = json.loads(р.stdout)["hookSpecificOutput"]["permissionDecisionReason"] if р.stdout.strip() else ""
    return ("слово" if "звернене до тебе" in причина else "інше" if причина else "відходить") + (
        " +stderr" if р.stderr.strip() else "")


def main():
    with tempfile.TemporaryDirectory() as т:
        os.makedirs(os.path.join(т, "аудит"))
        with open(os.path.join(т, "аудит", "СТАН.md"), "w", encoding="utf-8") as ф:
            ф.write(СТАН)
        повтор = os.path.join(т, "повтор")
        лист_1 = 'СЛОВО ВЛАСНИКА 09:10 UTC: «"Чекаю на вільний слот" - чому чекаєш? Роби на іншій моделі.»'
        випадки = [
            ("відповідь на рядок у лапках", МЕНЕДЖЕР, лист_1, повтор, "слово"),
            ("той самий лист удруге", МЕНЕДЖЕР, лист_1, повтор, "відходить"),
            ("звертання на «ти»", МЕНЕДЖЕР, "СЛОВО ВЛАСНИКА 09:20 UTC: «Ти знову не відповів мені сам.»", повтор,
             "слово"),
            ("слово про продукт", МЕНЕДЖЕР,
             "СЛОВО ВЛАСНИКА 09:30 UTC: «Стилістка має пропонувати теплі тканини взимку.»", повтор, "відходить"),
            ("слово вкладене в «ЗВЕДЕННЯ»", МЕНЕДЖЕР,
             "ЗВЕДЕННЯ 10:00 UTC\nСлова власника: 09:40 «Скільки коштує один прогін на ноутбуці?»", повтор, "слово"),
            ("лист іншій сесії", "session_ІНША", "СЛОВО ВЛАСНИКА 09:20 UTC: «Ти знову не відповів мені сам.»",
             os.path.join(т, "повтор2"), "відходить"),
            ("файл відбитків не пишеться", МЕНЕДЖЕР, "СЛОВО ВЛАСНИКА 09:20 UTC: «Ти знову не відповів мені сам.»",
             os.path.join(т, "транскрипт.jsonl", "повтор"), "відходить +stderr"),
        ]
        збої = 0
        for назва, кому, текст, файл, чекано in випадки:
            факт = запуск(т, кому, текст, файл)
            збої += факт != чекано
            print(f"{'ок ' if факт == чекано else 'ЗБІЙ'} {назва} → {факт} (чекано {чекано})")
        print("збоїв:", збої)
        sys.exit(1 if збої else 0)


main()
