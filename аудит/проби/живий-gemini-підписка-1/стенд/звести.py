#!/usr/bin/env python3
"""Час, токени й ціна проби «Живий-gemini-підписка-1» (копія `живий-як-людина-1/стенд/звести.py`, режим `руки` — без змін):
модель продукту через `agy` (журнал_моделі_продукту.jsonl, по проходах) і сесії жінок (службове/<с>/жінка.json); режим `фото` —
відповіді крамниць на фото речей із службове/<с>/фото_речей.txt (скільки 200, скільки 403 — окремо `attico.ua`).
Запуск із теки стенд/: python звести.py > ціна.md ;  python звести.py фото > фото_крамниць.md
Режим `руки`: таблиця «ситуація · прохід · позиція на екрані → рука» і стан фото карток із службове/<с>/руки.jsonl, який
стенд пише сам із сторінки (людина.js, `знімокРук`): python3 звести.py руки > руки_таблиця.md   (наряд Стенд-як-людина-рука-образу)"""
import json, glob, os, collections, sys, re


def руки():
    """Остання (повніша) картина кожного збирання: прохід = порядок збирань у ситуації за `прогін`; рука — з ключа сторінки."""
    НАЗВА = {"1": "1", "2": "2 (код з поломкою)", "3": "3", "4": "4"}
    рядки, фото, поломки = [], [], []
    for т in sorted(glob.glob("службове/*/руки.jsonl")):
        с = os.path.basename(os.path.dirname(т)); збирання = collections.OrderedDict(); мережа = {}
        ж = os.path.join(os.path.dirname(т), "фото_речей.txt")  # відповіді мережі на картинки: «<час> <код|FAIL помилка> <url>»
        for л in (open(ж, encoding="utf8") if os.path.exists(ж) else []):
            ч = л.split()
            if len(ч) >= 3: мережа[ч[-1]] = " ".join(ч[1:-1])
        for л in open(т, encoding="utf8"):
            з = json.loads(л)
            if not з.get("прогін"): continue  # без показаних карток (`П`) це не прохід
            if з.get("готово") is False: з = {**з, "сід": None, "поломка_руки_2": {"діагноз": []}}  # метаданих показаного проходу не міняє
            ст = збирання.get(з["прогін"], {})  # позиції — останні; сід і поломку, що були відомі раніше, не стираємо
            збирання[з["прогін"]] = {**ст, **{к: в for к, в in з.items() if в not in (None, "") and к != "поломка_руки_2"},
                                     "поломка_руки_2": з["поломка_руки_2"] if з["поломка_руки_2"].get("діагноз") else ст.get("поломка_руки_2", з["поломка_руки_2"])}
        for н, з in enumerate(збирання.values(), 1):
            пози = {п["позиція"]: п for п in з["позиції"]}
            клітини = [НАЗВА.get(пози[i]["рука"], "?") if i in пози else "—" for i in range(1, 5)]
            рядки.append(f"| {с.split('_')[0]} · {н} | {з.get('сід')} | {з.get('ключ')} | " + " | ".join(клітини) + " |")
            for д in з.get("поломка_руки_2", {}).get("діагноз", []):
                if "hand_2_broken" in д:
                    поломки.append(f"| {с.split('_')[0]} · {н} | {д} |")
            for п in з["позиції"]:
                for ф in п["ф"]:
                    ст = ("силует (кадри вичерпано)" if ф.get("силует") else "завантажено" if ф["завантажено"]
                          else "помилка (завершено, 0 px)" if ф.get("завершено") else "не почато (lazy)" if ф.get("lazy") else "вантажиться")
                    src = ф.get("src") or ф.get("src_дані") or ""
                    фото.append((с.split("_")[0], н, п["позиція"], п["рука"], ф["ід"], src, ст + (f" · мережа: {мережа[src[:200]]}" if src[:200] in мережа else "")))
    print("| ситуація · прохід | сід | ключ (поз.1–4) | поз. 1 | поз. 2 | поз. 3 | поз. 4 |\n|---|---|---|---|---|---|---|")
    print("\n".join(рядки))
    print("\n## Поломка руки 2 (рядок діагнозу сторінки)\n\n| ситуація · прохід | діагноз |\n|---|---|")
    print("\n".join(поломки) if поломки else "| — | рядка нема |")
    разом = collections.Counter(ф[-1].split(' · ')[0] for ф in фото)
    print(f"\n## Фото карток: {len(фото)} зображень у `.ф` — " + ", ".join(f"{к}: {в}" for к, в in sorted(разом.items())))
    print("\n| ситуація · прохід | поз. | рука | річ | src | стан |\n|---|---|---|---|---|---|")
    for с, н, п, р, ід, src, ст in фото:
        print(f"| {с} · {н} | {п} | {р} | {ід} | {src[:90]} | {ст} |")


if len(sys.argv) > 1 and sys.argv[1] == "руки":
    руки(); sys.exit(0)
if len(sys.argv) > 1 and sys.argv[1] == "фото":
    за = collections.defaultdict(collections.Counter); усі = collections.Counter()
    for т in sorted(glob.glob("службове/*/фото_речей.txt")):
        с = os.path.basename(os.path.dirname(т)).split("_")[0]
        for л in open(т, encoding="utf8"):
            ч = л.split()
            if len(ч) < 3: continue
            хост = re.sub(r"^https?://([^/]+)/.*$", r"\1", ч[-1]); код = ч[1]
            за[хост][код] += 1; усі[код] += 1
    print("| хост | відповідей | 200 | 403 | 404 | інше (FAIL тощо) |\n|---|---|---|---|---|---|")
    for х, к in sorted(за.items(), key=lambda п: -sum(п[1].values())):
        print(f"| {х} | {sum(к.values())} | {к['200']} | {к['403']} | {к['404']} | {sum(в for з, в in к.items() if з not in ('200', '403', '404'))} |")
    print(f"| **усього** | {sum(усі.values())} | {усі['200']} | {усі['403']} | {усі['404']} | {sum(в for з, в in усі.items() if з not in ('200', '403', '404'))} |")
    sys.exit(0)
пр = collections.defaultdict(lambda: {"н": 0, "с": [], "не200": 0, "фото_нд": 0, "вх": 0, "кеш": 0, "вих": 0, "роз": 0})
for л in open("журнал_моделі_продукту.jsonl", encoding="utf8"):
    д = json.loads(л); з = пр[д["прохід"]]
    з["н"] += 1; з["с"].append(д["с"]); з["не200"] += д["статус"] != 200; з["фото_нд"] += д.get("фото_не_дійшло") or 0
    з["вх"] += д.get("вхід") or 0; з["кеш"] += д.get("кеш_читання") or 0; з["вих"] += д.get("вихід") or 0; з["роз"] += д.get("роздуми") or 0
print("| ситуація | викликів моделі | не 200 | фото не дійшло | секунд на виклик (медіана / макс) | вхід, ток. | вихід, ток. | з них роздуми | кроків жінки | $ жінки |")
print("|---|---|---|---|---|---|---|---|---|---|")
сума = collections.Counter()
for п in sorted(пр):
    ж = json.load(open(f"службове/{п}/жінка.json")) if os.path.exists(f"службове/{п}/жінка.json") else {}
    з = пр[п]; с = sorted(з["с"]); м = с[len(с) // 2]
    print(f"| {п} | {з['н']} | {з['не200']} | {з['фото_нд']} | {м:.0f} / {max(с):.0f} | {з['вх']} | {з['вих']} | {з['роз']} | {ж.get('кроків', '—')} | {ж.get('usd', 0):.2f} |")
    for к in ("н", "не200", "фото_нд", "вх", "вих", "роз"): сума[к] += з[к]
    сума["жк"] += ж.get("кроків", 0); сума["жд"] += ж.get("usd", 0)
print(f"| **разом** | {сума['н']} | {сума['не200']} | {сума['фото_нд']} | | {сума['вх']} | {сума['вих']} | {сума['роз']} | {сума['жк']} | {сума['жд']:.2f} |")
