#!/bin/bash
# Серія проходів жінки на місцевому мосту до `agy` (ноутбук Admin, Git Bash; імена змінних латиницею — bash іншого не знає).
# Відновлювана: ситуація з `повідомлення.md` — пропуск; почата й обірвана — з початку. Запуск (з теки живий-gemini-підписка-1):
#   bash стенд/серія.sh <тека_моделі> <agy_модель> <модель_продукту_в_посиланні> <порт> <паралельно> [ситуації через пробіл]
# Потрібно в середовищі: STOR (тека з index.html збірки), PYODIDE (кеш Pyodide 0.26.4), ZHYVA_BIN (claude.exe),
# NODE_PATH (playwright). Ситуації й пам'ятку бере з `живий-як-людина-1/` дослівно.
cd "$(dirname "$0")/.."
M=$1; AM=$2; PM=$3; PORT=$4; PAR=$5; shift 5
SIT=${*:-"с1_новорічна_вечірка с2_мінус_вісім_офіс с3_дощ_замшеві_чоботи с4_побачення_19_30 с5_весілля_сестри с6_ювілей_свекрухи с7_театр_тріада с8_мінус_десять_сніг"}
mkdir -p "$M/стенд"
cp "../живий-як-людина-1/пам'ятка.md" "$M/пам'ятка.md"
for s in $SIT; do mkdir -p "$M/$s"; cp "../живий-як-людина-1/$s/ситуація.md" "$M/$s/ситуація.md"; done
python -c "import socket;socket.create_connection(('127.0.0.1',$PORT),1)" 2>/dev/null || {
  AGY_MODEL=$AM nohup python стенд/міст_agy.py $PORT "$M/стенд/журнал_моделі_продукту.jsonl" "$M/стенд/записи" $AM >> "$M/стенд/міст.лог" 2>&1 &
  sleep 3; }
one() {
  M=$1; PORT=$2; t=$3
  [ -f "$M/$t/повідомлення.md" ] && { echo "$t уже готова"; return; }
  rm -rf "$M/$t/хід.md" "$M/$t/знімки" "$M/стенд/службове/$t" "$M/$t"/*.json
  echo "$(date -u +%H:%M:%S) старт $t"
  node стенд/людина.js "$M/$t" $PORT 320 > "$M/стенд/$t.лог" 2>&1
  echo "$(date -u +%H:%M:%S) кінець $t rc=$?"
}
export -f one; export PRODUCT_MODEL=$PM
echo $SIT | tr ' ' '\n' | xargs -P $PAR -I{} bash -c "one '$M' $PORT {}"
echo КІНЕЦЬ
