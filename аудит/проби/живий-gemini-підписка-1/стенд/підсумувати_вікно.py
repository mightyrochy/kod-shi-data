models = {}
for name in names:
    folder = base / name
    summary = json.loads((folder / 'зведення.json').read_text(encoding='utf-8'))
    audit = json.loads((attempt / name / 'перевірка_даних.json').read_text(encoding='utf-8'))
    assert not audit['помилки_повноти']
    assert not audit['збої_моделі']
    hands_path = folder / 'руки.md'
    hands = hands_path.read_text(encoding='utf-8').split('\n<!-- відсутні-картки -->')[0]
    first_run_pass = {}
    views = []
    for m in re.finditer(r'^- (.+?) · ([12]) · [1-4] → рука [1-4]; прогін (\S+)', hands, re.M):
        scene, phase, run = m[1], int(m[2]), m[3].rstrip(';')
        views.append((scene, phase, run))
        first_run_pass[(scene, run)] = min(phase, first_run_pass.get((scene, run), phase))
    new_shown = {(s, p) for s, p, r in views if p == first_run_pass[(s, r)]}
    missing = [(s, p) for s in summary['ситуації'] for p in (1, 2) if (s, p) not in new_shown]
    if missing:
        hands += '\n<!-- відсутні-картки -->\n\nПроходи без показаного нового збирання:\n\n'
        hands += ''.join(f'- {s} · {p} · нові картки не показані; повторний показ попередніх карток, якщо був, позначено вище за ідентифікатором прогону. Подія й докази — у звіті збоїв.\n' for s, p in missing)
    hands_path.write_text(hands, encoding='utf-8')
    models[name] = {'ситуацій': len(summary['ситуації']), 'проходів': 2 * len(summary['ситуації']),
                    'кадрів': sum(s['кадрів'] for s in audit['ситуації'].values()),
                    'введено': sum(s['введено'] for s in audit['ситуації'].values()),
                    'пропущено': sum(s['пропущено'] for s in audit['ситуації'].values()),
                    'розбіжностей_дій': sum(s['розбіжностей'] for s in summary['ситуації'].values()),
                    'викликів': summary['викликів'], 'фото': summary['фото_моста'],
                    'attico_200': summary['attico_браузер'].get('200', 0),
                    'attico_403': summary['attico_браузер'].get('403', 0),
                    'токени': summary['токени'], 'без_нового_показаного_збирання': missing,
                    'ситуації': summary['ситуації']}
