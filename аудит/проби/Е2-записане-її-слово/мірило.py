"""Мірило наряду Картка-записане-її-слово (К5): с8 і с5 на записаній відповіді моделі (перший хід розмови, прохід 1,
`аудит/проби/живий-як-людина-4/стенд/службове/<сцена>/обміни.jsonl.gz`, виклик 0) крізь код ДО (`git show <БАЗА>:`)
і ПІСЛЯ (дерево). Друкує: (1) факти, що є в «Твоїх словах» і в записі, але не мають рядка картки; (2) факти без рядка й
без позначки «не записано» (мовчки зниклі); (3) речення стилістки прозою про записане, які покаже бульбашка.
Запуск з кореня: python3 аудит/проби/Е2-записане-її-слово/мірило.py [БАЗА=origin/main]"""
import contextlib, gzip, io, json, os, subprocess, sys, tempfile

КОРІНЬ = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
БАЗА = sys.argv[1] if len(sys.argv) > 1 else "origin/main"
СЦЕНИ = {"с8_мінус_десять_сніг": "на вулиці мінус десять і сніг, йду на роботу пішки 20 хвилин",
         "с5_весілля_сестри": "я гостя на весіллі сестри в серпні, церемонія надворі о 16:00, потім ресторан"}
ТЕКА = os.path.join(КОРІНЬ, "аудит/проби/живий-як-людина-4/стенд/службове")


def завантажити(корінь_джерел):
    sys.path.insert(0, корінь_джерел)
    for м in [м for м in sys.modules if м in ("мовний_шар", "паспорт_поля", "паспорт_нагоди", "картка_запиту")]:
        del sys.modules[м]
    with contextlib.redirect_stdout(io.StringIO()):
        import мовний_шар, паспорт_поля
    sys.path.remove(корінь_джерел)
    return мовний_шар, паспорт_поля


def дерево_бази():
    т = tempfile.mkdtemp(prefix="база_")
    архів = subprocess.run(["git", "archive", БАЗА, "джерела"], cwd=КОРІНЬ, capture_output=True, check=True).stdout
    subprocess.run(["tar", "x", "-C", т], input=архів, check=True)
    return os.path.join(т, "джерела")


def перша_відповідь(сцена):
    for р in (json.loads(л) for л in gzip.open(os.path.join(ТЕКА, сцена, "обміни.jsonl.gz"), "rt")):
        текст = json.loads(р["відповідь"])["content"][0]["text"]
        if '"update"' in текст:
            return текст


def виміряти(м, пп, сцена, слова):
    пр = м.прийняти_розмову(перша_відповідь(сцена))
    with contextlib.redirect_stdout(io.StringIO()):
        р = м.паспорт_з_шару(пр["внутрішня"], {}, слова_ходу=[слова], частини=пр["частини"])
    п = р["паспорт"]
    уривки = {п_: у for п_, у in (п.get("цитати_полів") or {}).items() if у}
    # рядок картки на ДО — поле з екранним елементом (`показ`); ПІСЛЯ — ще й загальний (`назва_картки`)
    опис = lambda к: пп.ПОЛЯ_ПАСПОРТА.get(к, {})
    є_рядок = lambda к: "показ" in опис(к) or "назва_картки" in опис(к) or к in ("подія", "решта")
    факти = {к: у for к, у in уривки.items() if к in пп.ПОЛЯ_ПАСПОРТА and (п.get(к) not in (None, "", []))}
    година = "пора" in факти and any(ц.isdigit() for ц in факти["пора"])
    без_рядка = sorted(к for к in факти if not є_рядок(к)) + (["пора:година"] if година and "назва_уривка_картки" not in опис("пора") else [])
    прозою = [x for x, прийнято in р.get("речення_показу", []) if прийнято]
    # мовчки зниклі: її уривок поля (`quotes` відповіді моделі), чиє значення не лягло в запис, а слова не стоять у `решта`
    # чи `не_взято_кодом` — ні рядка, ні позначки «не записано»
    модельні = (пр["внутрішня"].get("quotes") or {})
    решта = " ".join(str(x) for x in [п.get("решта") or [], п.get("не_взято_кодом") or []])
    ключ = {в["поле"]: к for к, в in пп.ПОЛЯ_ПАСПОРТА.items() if в.get("поле")}
    ключ.update({"precipitation": "опади"})                  # у реєстрі без коду дроту
    # `occasion_part` — службовий код частини нагоди (`картка_запиту.СЛУЖБОВІ`), факту не несе
    зниклі = sorted(к for к, у in модельні.items() if у and к in ключ and к != "occasion_part" and п.get(ключ[к]) in (None, "", [])
                    and str(у) not in решта)
    return факти, без_рядка, прозою, зниклі


for назва, корінь in (("ДО", дерево_бази()), ("ПІСЛЯ", os.path.join(КОРІНЬ, "джерела"))):
    м, пп = завантажити(корінь)
    for сцена, слова in СЦЕНИ.items():
        факти, без_рядка, прозою, зниклі = виміряти(м, пп, сцена, слова)
        print("%s · %s · факти в «Твоїх словах» із записом: %d · без рядка картки: %d %s · мовчки зниклих: %d %s · речень прозою про записане: %d"
              % (назва, сцена, len(факти), len(без_рядка), без_рядка, len(зниклі), зниклі, len(прозою)))
        for x in прозою:
            print("   «%s»" % x)
