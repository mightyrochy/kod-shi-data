"""Мірило наряду Картка-записане-її-слово (К5): с8 і с5 на записаних відповідях моделі першого живого прогону через міст
(`аудит/проби/Живий-через-міст/стенд/службове/<сцена>/обміни.jsonl`, прохід 1 і 2, остання відповідь розмови з `update`)
крізь код ДО (`git archive <БАЗА>`) і ПІСЛЯ (дерево). Паспорт — той, що дає `паспорт_з_шару` (`мовний_шар.паспорт_з_шару`), без
рукописних об'єктів; рядки картки ПІСЛЯ малює справжній `показ` (`знімок.js` РЕЖИМ=рядки: `застосуватиПаспортДоЕкрана` →
малювач `записане-її`), а не Python-словник. Друкує на кожну сцену й прохід: (1) факти на її словах із записом без рядка
картки; (2) факти без рядка й без позначки «не записано» (мовчки зниклі); (3) речення стилістки прозою про записане, які
покаже бульбашка; (4) для с5 — чи збігаються рядки картки двох проходів (вада 11) і чи рядок каже записане значення, а не
уривок. Запуск з кореня: python3 аудит/проби/Е2-записане-її-слово/мірило.py [БАЗА=origin/main]"""
import contextlib, io, json, os, subprocess, sys, tarfile, tempfile

КОРІНЬ = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
БАЗА = sys.argv[1] if len(sys.argv) > 1 else "origin/main"
СЦЕНИ = {"с8_мінус_десять_сніг": "на вулиці мінус десять і сніг, йду на роботу пішки 20 хвилин",
         "с5_весілля_сестри": "я гостя на весіллі сестри в серпні, церемонія надворі о 16:00, потім ресторан"}
ТЕКА = os.path.join(КОРІНЬ, "аудит/проби/Живий-через-міст/стенд/службове")
ПРОБА = os.path.join(КОРІНЬ, "аудит/проби/Е2-записане-її-слово")


def завантажити(корінь_джерел):
    sys.path.insert(0, корінь_джерел)
    for м in [м for м in sys.modules if м in ("мовний_шар", "паспорт_поля", "паспорт_нагоди", "картка_запиту")]:
        del sys.modules[м]
    with contextlib.redirect_stdout(io.StringIO()):
        import мовний_шар, паспорт_поля
    sys.path.remove(корінь_джерел)
    return мовний_шар, паспорт_поля


def дерево_бази():
    т = tempfile.mkdtemp(prefix="база_")
    архів = subprocess.run(["git", "archive", БАЗА, "джерела"], cwd=КОРІНЬ, capture_output=True, check=True).stdout
    with tarfile.open(fileobj=io.BytesIO(архів)) as а:      # tarfile, а не `tar` зі stdin: однаково на Linux і Windows
        а.extractall(т, filter="data") if hasattr(tarfile, "data_filter") else а.extractall(т)
    return т


def відповіді(сцена):
    """{прохід: остання відповідь розмови з `update`} — прийнята відповідь проходу."""
    вих = {}
    for р in (json.loads(л) for л in open(os.path.join(ТЕКА, сцена, "обміни.jsonl"), encoding="utf-8")):
        try:
            текст = json.loads(р["відповідь"])["content"][0]["text"]
        except (KeyError, ValueError, TypeError, IndexError):
            continue
        if '"update"' in текст:
            вих[р["прохід"]] = текст
    return вих


def складено(м, сцена, прохід, текст, слова):
    пр = м.прийняти_розмову(текст)
    with contextlib.redirect_stdout(io.StringIO()):
        р = м.паспорт_з_шару(пр["внутрішня"], {}, слова_ходу=[слова], частини=пр["частини"])
    return пр, р


def факти_на_її_словах(п, пп):
    """Факти картки запиту на її словах — поля запису з переліку (`ПОЛЯ_ПАСПОРТА`), чиє значення не порожнє."""
    вих = {}
    for к, ф in (п.get("картка_запиту") or {}).items():
        if к in пп.ПОЛЯ_ПАСПОРТА and пп.ПОЛЯ_ПАСПОРТА[к].get("цитата") in ("пара", "речі") and ф.get("джерело") in ("her", "hand", "reading") and str(ф.get("уривок") or "").strip() \
                and ф.get("значення") not in (None, "", [], "невідомо"):
            вих[к] = ф
    return вих


def рядки_картки(файл, мітка, коріньБудови):
    """Рядки, які малює справжній показ дерева `коріньБудови` для паспортів з файла."""
    н = dict(os.environ, ПАСПОРТИ=файл, LBL=мітка, РЕЖИМ="рядки", NODE_PATH="node_modules")
    скрипт = os.path.join(ПРОБА, "знімок.js")
    return json.loads(subprocess.run(["node", скрипт], cwd=os.path.join(коріньБудови, "джерела"), env=н, capture_output=True,
                                     text=True, check=True).stdout)


def виміряти(мітка, кореньДжерел, коріньБудови):
    м, пп = завантажити(кореньДжерел)
    паспорти, зріз = {}, {}
    for сцена, слова in СЦЕНИ.items():
        for прохід, текст in sorted(відповіді(сцена).items()):
            пр, р = складено(м, сцена, прохід, текст, слова)
            паспорти["%s/%d" % (сцена, прохід)] = р["паспорт"]
            зріз["%s/%d" % (сцена, прохід)] = (пр, р)
    файл = os.path.join(tempfile.mkdtemp(), "паспорти-%s.json" % мітка)
    json.dump(паспорти, open(файл, "w", encoding="utf-8"), ensure_ascii=False, default=str)
    рядки = рядки_картки(файл, мітка, коріньБудови) if коріньБудови else {}
    return м, пп, паспорти, зріз, рядки, файл


def друк(мітка, м, пп, паспорти, зріз, рядки):
    for ключ, п in паспорти.items():
        пр, р = зріз[ключ]
        факти = факти_на_її_словах(п, пп)
        речі = {к for к in факти if (пп.ПОЛЯ_ПАСПОРТА[к].get("цитата") == "речі")}
        в_рядках = {рр["поле"] for рр in (рядки.get(ключ) or {}).get("рядки", []) if рр["поле"]}
        інші = lambda к: "показ" in пп.ПОЛЯ_ПАСПОРТА[к] or "рядок_картки_свій" in пп.ПОЛЯ_ПАСПОРТА[к]
        # ДО рядок мали лише поля з екранним елементом (`показ`); ПІСЛЯ — ще й поля, що справді намалювала картка
        є_рядок = (lambda к: інші(к) or к in в_рядках) if мітка == "ПІСЛЯ" else (lambda к: "показ" in пп.ПОЛЯ_ПАСПОРТА[к])
        без = sorted(к for к in факти if к not in речі and not є_рядок(к))
        прозою = [x for x, прийнято in р.get("речення_показу", []) if прийнято]
        модельні = (пр["внутрішня"].get("quotes") or {})
        решта = " ".join(str(x) for x in [п.get("решта") or [], п.get("не_взято_кодом") or []])
        поле_до_ключа = {в["поле"]: м._імʼя_факту(к) for к, в in пп.ПОЛЯ_ПАСПОРТА.items() if в.get("поле") and м._імʼя_факту(к)}
        зниклі = sorted(к for к, у in модельні.items() if у and к in поле_до_ключа and к != "occasion_part"
                        and п.get(поле_до_ключа[к]) in (None, "", []) and str(у) not in решта)
        print("%s · %s · фактів на її словах із записом: %d · без рядка картки: %d %s · мовчки зниклих: %d %s · речень прозою про записане: %d"
              % (мітка, ключ, len(факти), len(без), без, len(зниклі), зниклі, len(прозою)))
        for x in прозою:
            print("   «%s»" % x)
        for рр in (рядки.get(ключ) or {}).get("рядки", []):
            print("   рядок: %s — %s%s" % (рр["назва"], рр["текст"], " [кнопка]" if рр["кнопка"] else ""))


# ДО: знімок бази — її дерево, рядків «записане» там нема (малювача нема), тож рядки не друкуємо
база = дерево_бази()
друк("ДО", *виміряти("ДО", os.path.join(база, "джерела"), None)[:5])
м, пп, паспорти, зріз, рядки, файл = виміряти("ПІСЛЯ", os.path.join(КОРІНЬ, "джерела"), КОРІНЬ)
друк("ПІСЛЯ", м, пп, паспорти, зріз, рядки)
for сцена in СЦЕНИ:
    проходи = sorted(к for к in рядки if к.startswith(сцена + "/"))
    тексти = [[(рр["назва"], рр["текст"]) for рр in рядки[к]["рядки"]] for к in проходи]
    print("ПІСЛЯ · %s · проходів %d · рядки картки збігаються між проходами: %s" % (сцена, len(проходи), all(т == тексти[0] for т in тексти)))
print("паспорти ПІСЛЯ для знімків: %s" % файл)
