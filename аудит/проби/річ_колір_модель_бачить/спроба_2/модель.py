# -*- coding: utf-8 -*-
"""`модель.jsonl` (усі записи моделі з часом, зокрема виправлені версії) → `модель.tsv` (остання версія кожного номера).

Родина — сім'я коду моделі в `словник_кольору` (`СІМ_Я`), кадр і річ — з `кадри.tsv`. Записи робить модель зору до
виміру; скрипт лише зводить їх у таблицю, нічого не міряє. Запуск із кореня:
`python3 -I аудит/проби/річ_колір_модель_бачить/спроба_2/модель.py`.
"""
import csv
import json
import os
import sys

ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(ТУТ, "..", "..", "..", "..", "джерела"))
import словник_кольору as СК  # noqa: E402

ПОЛЯ = ("номер", "річ", "кадр", "код", "родина", "принт", "інші_коди", "тло", "тло_опис", "світло", "ділянка",
        "що_поза", "версія", "час_utc", "примітка")


def головна():
    with open(os.path.join(ТУТ, "кадри.tsv"), encoding="utf-8") as ф:
        кадри = {int(р["номер"]): р for р in csv.DictReader(ф, delimiter="\t")}
    останні = {}
    with open(os.path.join(ТУТ, "модель.jsonl"), encoding="utf-8") as ф:
        for рядок in ф:
            з = json.loads(рядок)
            останні[з["номер"]] = з
    assert sorted(останні) == sorted(кадри), "записи моделі не на всіх кадрах"
    with open(os.path.join(ТУТ, "модель.tsv"), "w", encoding="utf-8", newline="") as ф:
        п = csv.writer(ф, delimiter="\t", lineterminator="\n")
        п.writerow(ПОЛЯ)
        for н in sorted(останні):
            з, к = останні[н], кадри[н]
            for код in [з["код"]] + з["інші_кольори"]:
                assert код in СК.СЛОВО, "код поза словником: %s" % код
            п.writerow((н, к["річ"], к["кадр"], з["код"], СК.СІМ_Я[СК.СЛОВО[з["код"]]], з["принт"],
                        " ".join(з["інші_кольори"]), з["тло"], з["тло_опис"], з["світло"],
                        json.dumps(з["ділянка"]["прямокутники"]), з["що_поза"], з.get("версія", 1), з["час_utc"],
                        з["примітка"]))
    print("записів %d, номерів %d" % (sum(1 for _ in open(os.path.join(ТУТ, "модель.jsonl"), encoding="utf-8")),
                                     len(останні)))


if __name__ == "__main__":
    головна()
