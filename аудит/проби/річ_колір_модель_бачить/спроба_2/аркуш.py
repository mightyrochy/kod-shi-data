# -*- coding: utf-8 -*-
"""Аркуш нових 40 для двох оглядачів ПІСЛЯ: кадр · латка ПІСЛЯ · код · стан · межі · родина моделі.

Кадр — з рамками ділянки, яку назвала модель і в якій міряв код (блакитні); під кадром — латка точки коду (hex),
код точки за правилом спроби 2 (вікно коду чи родини моделі; «—» — жодного), стан, модель (код, родина, принт з його
кольорами, тло) і для «не певний» — межі обох прочитань: виміру (L*, C*, тон) і моделі (родини, чиї вікна несе межа;
вікна — `межі_моделі` у `вимір.tsv`). ДО-виміру, вердиктів і власних суджень тут нема. `аркуш_1.jpg` — речі 1–20,
`аркуш_2.jpg` — 21–40; `аркуш.tsv` — ті самі дані текстом з порожніми колонками вердиктів.

Запуск із кореня (після `git fetch origin claude/Річ-колір-вимір`):
`python3 -I аудит/проби/річ_колір_модель_бачить/спроба_2/аркуш.py`.
"""
import csv
import io
import json
import os
import subprocess
import sys
import textwrap

from PIL import Image, ImageDraw, ImageFont, ImageOps

ТУТ = os.path.dirname(os.path.abspath(__file__))
КОРІНЬ = os.path.abspath(os.path.join(ТУТ, "..", "..", "..", ".."))
sys.path.insert(0, os.path.join(КОРІНЬ, "джерела"))
import словник_кольору as СК  # noqa: E402

ДАНІ = "43dd34adee5bf462c70cbdc9f01719da7250719e"
ТЕКА_ДАНИХ = "аудит/проби/річ_колір_перезбір_0411/"
ШРИФТ = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
КОЛОНОК, РЯДІВ, Ш, В, ФОТО = 5, 4, 380, 690, 470


def кадр(шлях):
    байти = subprocess.run(["git", "-C", КОРІНЬ, "show", ДАНІ + ":" + ТЕКА_ДАНИХ + шлях],
                           check=True, capture_output=True).stdout
    return Image.open(io.BytesIO(байти)).convert("RGB")


def межі_виміру(м):
    L0, L1, C0, C1, дуга = json.loads(м)
    return "L* %.0f–%.0f · C* %.0f–%.0f · %s" % (L0, L1, C0, C1, "тон %d–%d°" % tuple(дуга) if дуга else "тон будь-який")


def межі_моделі(м):
    return " + ".join(json.loads(м))


def код_точки(в):
    return "%s (%s)" % (в["код_точки"], СК.СЛОВО[в["код_точки"]]) if в["код_точки"] else "— (жодного вікна родини)"


def модель_текстом(м):
    return "модель: %s (%s) · %s" % (м["код"], СК.СЛОВО[м["код"]], м["родина"])


def принт_текстом(м):
    принт = "принт так: %s" % ", ".join(м["інші_коди"].split()) if м["принт"] == "так" else "принт ні"
    return "%s · тло %s" % (принт, м["тло"])


def клітинка(олівець, аркуш, x, y, м, в, ф, фж):
    фото = кадр(м["кадр"])
    W, H = фото.size
    мал = ImageDraw.Draw(фото)
    товщина = max(3, round(max(W, H) / 250))
    for x0, y0, x1, y1 in json.loads(м["ділянка"]):
        мал.rectangle((x0, y0, x1, y1), outline="#00b7ff", width=товщина)
    фото = ImageOps.contain(фото, (Ш - 10, ФОТО))
    аркуш.paste(фото, (x + (Ш - фото.width) // 2, y + 4))
    олівець.rectangle((x + 1, y + 1, x + Ш - 2, y + В - 2), outline="#bbbbbb", width=1)
    номер, крамниця = м["річ"].split("@", 1)
    т = y + ФОТО + 8
    олівець.text((x + 8, т), "%s. %s · %s" % (м["номер"], номер, крамниця[:26]), fill="black", font=фж)
    олівець.rectangle((x + 8, т + 22, x + 58, т + 72), fill=в["hex"], outline="black")
    олівець.text((x + 66, т + 22), код_точки(в), fill="black", font=фж)
    олівець.text((x + 66, т + 42), "%s · %s" % (в["hex"], в["родина_точки"] or "—"), fill="black", font=ф)
    не_певний = в["стан"] != "певний"
    олівець.text((x + 66, т + 58), в["стан"], fill="#c05000" if не_певний else "#006000", font=фж)
    олівець.text((x + 8, т + 80), модель_текстом(м), fill="black", font=ф)
    рядок = т + 97
    for шматок in textwrap.wrap(принт_текстом(м), 50):
        олівець.text((x + 8, рядок), шматок, fill="black", font=ф)
        рядок += 17
    if не_певний:
        олівець.text((x + 8, рядок), "межі виміру: " + межі_виміру(в["межі_виміру"]), fill="#c05000", font=ф)
        рядок += 17
        for шматок in textwrap.wrap("межі моделі: " + межі_моделі(в["межі_моделі"]), 50):
            олівець.text((x + 8, рядок), шматок, fill="#c05000", font=ф)
            рядок += 17


def головна():
    with open(os.path.join(ТУТ, "модель.tsv"), encoding="utf-8") as ф:
        модель = list(csv.DictReader(ф, delimiter="\t"))
    with open(os.path.join(ТУТ, "вимір.tsv"), encoding="utf-8") as ф:
        вимір = {р["номер"]: р for р in csv.DictReader(ф, delimiter="\t")}
    ф, фж = ImageFont.truetype(ШРИФТ, 13), ImageFont.truetype(ШРИФТ.replace("Sans.", "Sans-Bold."), 15)
    на_аркуш = КОЛОНОК * РЯДІВ
    for а in range(0, len(модель), на_аркуш):
        аркуш = Image.new("RGB", (КОЛОНОК * Ш, РЯДІВ * В), "white")
        олівець = ImageDraw.Draw(аркуш)
        for і, м in enumerate(модель[а:а + на_аркуш]):
            клітинка(олівець, аркуш, (і % КОЛОНОК) * Ш, (і // КОЛОНОК) * В, м, вимір[м["номер"]], ф, фж)
        аркуш.save(os.path.join(ТУТ, "аркуш_%d.jpg" % (а // на_аркуш + 1)), quality=85)
    поля = ("номер", "річ", "кадр", "ділянка_моделі", "hex_ПІСЛЯ", "код_ПІСЛЯ", "стан", "межі_виміру", "межі_моделі",
            "вікна_меж_моделі", "модель", "принт_і_тло_моделі", "вердикт_оглядача", "причина_оглядача")
    with open(os.path.join(ТУТ, "аркуш.tsv"), "w", encoding="utf-8", newline="") as вих:
        п = csv.writer(вих, delimiter="\t", lineterminator="\n")
        п.writerow(поля)
        for м in модель:
            в = вимір[м["номер"]]
            не_певний = в["стан"] != "певний"
            п.writerow((м["номер"], м["річ"], м["кадр"], м["ділянка"], в["hex"], код_точки(в), в["стан"],
                        межі_виміру(в["межі_виміру"]) if не_певний else "",
                        межі_моделі(в["межі_моделі"]) if не_певний else "",
                        в["межі_моделі"] if не_певний else "",
                        модель_текстом(м)[len("модель: "):], принт_текстом(м), "", ""))


if __name__ == "__main__":
    головна()
