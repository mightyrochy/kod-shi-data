# -*- coding: utf-8 -*-
"""Запасні речі набору 2 огляду кольору людьми: наступні речі того самого зерна 202611082 (наряд
`Річ-колір-огляд-людьми`, «Ціль»: запасні — наступні речі того самого зерна, із записами моделі до виміру й виміром тим
самим кодом проби, що й 40).

Як «наступні». `../вибірка.py` бере генератором `random.Random(202611082)` 40 речей (`sample`) і по кадру кожної
(`choice`). Тут той самий генератор після цих 80 кроків іде далі: запасна k — `choice` з решти речей сукупності
(відсортованих), її кадр — `choice` з її змінених кадрів, по одній. Перші 40 і їхні кадри не змінюються (скрипт звіряє
їх із `../кадри.tsv` рядок у рядок), а запасних можна взяти більше тим самим скриптом — перші не зміняться.

Вихід — те саме, що бачить модель до виміру в 40: `кадри.tsv` (номери 41…) і кадри в теку з аргументу; hex, коду й
кольору крамниці нема. Запуск із кореня (після `git fetch origin claude/Річ-колір-вимір`):
python3 -I аудит/проби/річ_колір_модель_бачить/спроба_2/запасні/вибірка.py <тека_фото> [число запасних, 10]
"""
import csv
import importlib.util
import random
import sys
from pathlib import Path

ТУТ = Path(__file__).resolve().parent
_с = importlib.util.spec_from_file_location("вибірка_спроби_2", ТУТ.parent / "вибірка.py")
В = importlib.util.module_from_spec(_с)
_с.loader.exec_module(В)


def головна():
    тека_фото = Path(sys.argv[1])
    запасних = int(sys.argv[2]) if len(sys.argv) > 2 else 10
    тека_фото.mkdir(parents=True, exist_ok=True)
    с = В.сукупність()
    спроба_1 = set(random.Random(В.ЗЕРНО_СПРОБИ_1).sample(sorted(с), В.РЕЧЕЙ))
    генератор = random.Random(В.ЗЕРНО)
    обрані = генератор.sample(sorted(set(с) - спроба_1), В.РЕЧЕЙ)
    кадри_40 = [генератор.choice(с[ід])[1]["фото"] for ід in обрані]
    with (ТУТ.parent / "кадри.tsv").open(encoding="utf-8") as ф:
        записані = [(р["річ"], р["кадр"]) for р in csv.DictReader(ф, delimiter="\t")]
    assert записані == list(zip(обрані, кадри_40)), "40 речей і кадри не збіглися з ../кадри.tsv"
    решта = sorted(set(с) - спроба_1 - set(обрані))
    запасні = []
    for _ in range(запасних):
        ід = генератор.choice(решта)
        решта.remove(ід)
        запасні.append((ід, генератор.choice(с[ід])))
    кат = В.категорії({ід.split("@")[0] for ід, _ in запасні})
    рядки = []
    for номер, (ід, (в, м)) in enumerate(запасні, В.РЕЧЕЙ + 1):
        (тека_фото / ("%02d.jpg" % номер)).write_bytes(В.показати(м["фото"]))
        категорія, тип = кат.get(ід.split("@")[0], ("", ""))
        рядки.append(dict(номер=номер, річ=ід, кадр=м["фото"], клас=в.get("клас") or "", категорія=категорія, тип=тип))
    with (ТУТ / "кадри.tsv").open("w", encoding="utf-8", newline="") as файл:
        писар = csv.DictWriter(файл, fieldnames=list(рядки[0]), delimiter="\t", lineterminator="\n")
        писар.writeheader()
        писар.writerows(рядки)
    print("40 збіглися з ../кадри.tsv; запасних %d (номери %d–%d) з решти %d" % (
        len(рядки), В.РЕЧЕЙ + 1, В.РЕЧЕЙ + len(рядки), len(решта) + len(рядки)))


if __name__ == "__main__":
    головна()
