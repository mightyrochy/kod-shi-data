# -*- coding: utf-8 -*-
"""Нове зерно 40 речей тієї самої дельти для спроби 2 проби «модель бачить» (наряд, «Спроба 2»).

Сукупність — та сама, що на прийманні 08.11 (`../../річ_колір_приймання_0811/вибірка.py`, рядок у рядок): речі
дельти перезбору (гілка даних `claude/Річ-колір-вимір`, голова ГОЛОВА), де хоч один кадр має придатний вимір
(`колір_тип` «вимір», `придатна`) з hex, відмінним від старого, і фото в маніфесті. З неї вилучено 40 речей
спроби 1 (їх дає те саме вибирання з зерном приймання 20261108 — без читання `вибірка.tsv`). Річ — рівноймовірно
з решти (`random.Random(ЗЕРНО).sample` по відсортованих id), кадр речі — рівноймовірно з її змінених кадрів тим
самим генератором, як на прийманні. ЗЕРНО — дата проби й номер спроби (2026-11-08, 2), назване до вибирання.

Вихід — лише те, що бачить модель до виміру: `кадри.tsv` (номер, річ, кадр, клас кадру, категорія каталогу,
`тип` каталогу — слово типу речі, не кольору) і фото 40 кадрів у теку з аргументу. Ні hex, ні коду перезбору,
ні назви й кольору крамниці тут нема: записи моделі робляться до виміру (свідок).

Запуск із кореня репозиторію (після `git fetch origin claude/Річ-колір-вимір`):
python3 -I аудит/проби/річ_колір_модель_бачить/спроба_2/вибірка.py <тека_фото>
"""
import csv
import gzip
import html
import json
import random
import re
import subprocess
import sys
from pathlib import Path

ГОЛОВА = "43dd34adee5bf462c70cbdc9f01719da7250719e"
ТЕКА_ДАНИХ = "аудит/проби/річ_колір_перезбір_0411/"
ЗЕРНО_СПРОБИ_1 = 20261108
ЗЕРНО = 202611082
РЕЧЕЙ = 40
ТУТ = Path(__file__).resolve().parent
КОРІНЬ = ТУТ.parents[3]


def показати(шлях):
    """Байти файла гілки даних на голові ГОЛОВА."""
    return subprocess.run(["git", "show", "%s:%s%s" % (ГОЛОВА, ТЕКА_ДАНИХ, шлях)], cwd=КОРІНЬ,
                          check=True, capture_output=True).stdout


def сукупність():
    """{id: [(запис, маніфест), …]} — як `річ_колір_приймання_0811/вибірка.py`."""
    дельта = json.loads(gzip.decompress(показати("дельта.json.gz")))
    до = json.loads(gzip.decompress(показати("кадри_ДО.json.gz")))["записи"]
    маніфест = {(м["id"], м["файл"], м["url"]): м for м in дельта["маніфест"]}
    вих = {}
    for ід, записи in дельта["записи"].items():
        старі = {в["файл"]: в for в in до[ід]}
        змінені = [(в, маніфест[ід, в["файл"], в["url"]]) for в in записи
                   if в.get("колір_тип") == "вимір" and в.get("придатна") is True and в.get("hex")
                   and в["hex"] != старі.get(в["файл"], {}).get("hex") and (ід, в["файл"], в["url"]) in маніфест]
        if змінені:
            вих[ід] = змінені
    return вих


def категорії(ід_без_крамниці):
    """{id: (категорія, тип)} з повного каталогу: назва `categoryId` і `param тип` (слово типу речі)."""
    текст = gzip.open(КОРІНЬ / "каталог_повний.xml.gz", "rt", encoding="utf-8").read()
    назви = dict(re.findall(r'<category id="([^"]+)"[^>]*>(.*?)</category>', текст))
    вих = {}
    for ід, тіло in re.findall(r'<offer id="([^"]+)"(.*?)</offer>', текст, re.S):
        if ід in ід_без_крамниці:
            к = re.search(r"<categoryId>(.*?)</categoryId>", тіло)
            т = re.search(r'<param name="тип">(.*?)</param>', тіло)
            вих[ід] = (назви.get(к.group(1), "") if к else "", html.unescape(т.group(1)) if т else "")
    return вих


def головна():
    тека_фото = Path(sys.argv[1])
    тека_фото.mkdir(parents=True, exist_ok=True)
    с = сукупність()
    спроба_1 = set(random.Random(ЗЕРНО_СПРОБИ_1).sample(sorted(с), РЕЧЕЙ))
    генератор = random.Random(ЗЕРНО)
    обрані = генератор.sample(sorted(set(с) - спроба_1), РЕЧЕЙ)
    кат = категорії({ід.split("@")[0] for ід in обрані})
    рядки = []
    for номер, ід in enumerate(обрані, 1):
        в, м = генератор.choice(с[ід])
        (тека_фото / ("%02d.jpg" % номер)).write_bytes(показати(м["фото"]))
        категорія, тип = кат.get(ід.split("@")[0], ("", ""))
        рядки.append(dict(номер=номер, річ=ід, кадр=м["фото"], клас=в.get("клас") or "",
                          категорія=категорія, тип=тип))
    with (ТУТ / "кадри.tsv").open("w", encoding="utf-8", newline="") as файл:
        писар = csv.DictWriter(файл, fieldnames=list(рядки[0]), delimiter="\t", lineterminator="\n")
        писар.writeheader()
        писар.writerows(рядки)
    print("сукупність %d речей; без спроби 1 — %d; зерно %d; обрано %d" % (
        len(с), len(set(с) - спроба_1), ЗЕРНО, len(рядки)))


if __name__ == "__main__":
    головна()
