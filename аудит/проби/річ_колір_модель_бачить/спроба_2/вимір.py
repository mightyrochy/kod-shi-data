"""Спроба 2 проби «модель бачить» (наряд, «Спроба 2»; паспорт `Річ-колір-вимір`, рішення 08.11 на огляд-1).

Вимір — рядок у рядок той, що в спробі 1 (`../вимір.py`, функції звідти: кадр, маска з прямокутників моделі,
поправка тла лише там, де модель сказала «тло біле»; точка — головний сегмент поверхні). Змінено два правила коду:

1. Код точки. З вікон коду, що вміщають точку (той самий тест, що в `surface.слово_з_lab`: L, C, а тон — лише
   для C* ≥ 10), код бере вікно, чий код бачить модель, а нема такого — найтісніше за L×C з вікон її родини; не
   найтісніше з усіх (14336: вибір геометрією, а не сприйняттям). Жодного вікна коду чи родини моделі серед тих,
   що вміщають точку, — «не певний».
2. Межі. «Не певний» несе межі обох прочитань: виміру (`surface.код_розкиду`: L*, C* ± U, дуга тону) і моделі —
   вікна слів родини, яку вона бачить, і родин кольорів принта, які вона назвала (`словник_кольору.СІМ_Ї` над
   вікнами `verify.ЛЕКСИКОН`, з вікнами слів поля крамниці).

Стан: «певний» — вікно з правила 1 є і весь розкид точки (шлях поправки тла, C ± U) у ньому (слово власника
08.11 10:07); «не певний» — інакше, з межами обох прочитань; «невідомо» — поверхня непридатна.

Запуск із кореня (після `git fetch origin claude/Річ-колір-вимір`):
`python3 -I аудит/проби/річ_колір_модель_бачить/спроба_2/вимір.py [записи моделі.tsv] [вихід.tsv]` —
без аргументів: `модель.tsv` → `вимір.tsv` тут; діагностика спроби 1 — `../модель.tsv` → `діагностика_1_вимір.tsv`.
Продукту й каталогу не міняє.
"""
