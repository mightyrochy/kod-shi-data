import словник_кольору as СК  # noqa: E402

_с = importlib.util.spec_from_file_location("вимір_спроби_1", os.path.join(ТУТ, "..", "вимір.py"))
В1 = importlib.util.module_from_spec(_с)
_с.loader.exec_module(В1)


def вікна_точки(lab):
    """[(площа L×C, слово)] вікон коду, що вміщають точку, — тест `surface.слово_з_lab` рядок у рядок."""
    L, C_, h = CS.lch(lab)
    вих = []
    for сл, (Lmin, Lmax, Cmin, Cmax, дуга) in П._вікна_коду():
        у_h = True if (not дуга or C_ < 10) else V.у_дузі(h, дуга)
        if Lmin <= L <= Lmax and Cmin <= C_ <= Cmax and у_h:
            вих.append(((Lmax - Lmin) * (Cmax - Cmin), сл))
    return sorted(вих)


def вікно_моделі(вміщають, слово_моделі):
    """Слово вікна за правилом 1: код моделі, інакше найтісніше з її родини; None — жодного."""
    родина = СК.СІМ_Я[слово_моделі]
    свої = [(0 if сл == слово_моделі else 1, площа, сл) for площа, сл in вміщають if СК.СІМ_Я[сл] == родина]
    return min(свої)[2] if свої else None


def розкид_у_вікні(lab, U, множники, слово):
    """Чи весь розкид точки (шлях поправки тла, C ± U, тон) у вікні слова — `surface._вміщає`, як `код_розкиду`."""
    точки = [CS.lch(т) for т in П.шлях_поправки(lab, множники)]
    return all(П._вміщає(V.ЛЕКСИКОН[слово], L, C, h, U) for L, C, h in точки)


def межі_моделі(код, інші_коди):
    """Межі прочитання моделі: {родина: {код: вікно}} — вікна `verify.ЛЕКСИКОН` усіх слів родини, яку вона бачить,
    і родин кольорів принта. Слова лише поля крамниці (тауп, мокко, рудий, джинсовий…) теж: їхні вікна — те, що продукт
    знає про ці слова, а код моделі буває саме таким словом (у першій редакції їх не було, і межі моделі не мали вікна її
    власного коду). Точку й код ці вікна не дають — лише межі."""
    родини = []
    for к in [код] + [к for к in інші_коди.split() if к]:
        р = СК.СІМ_Я[СК.СЛОВО[к]]
        if р not in родини:
            родини.append(р)
    return {р: {СК.КОД[сл]: list(V.ЛЕКСИКОН[сл]) for сл in СК.СІМ_Ї[р] if сл in V.ЛЕКСИКОН} for р in родини}


def рядок(з):
    """Запис моделі → рядок виміру спроби 2."""
    bgr = В1.кадр(з["кадр"])
    маска = В1.маска_ділянки(*bgr.shape[:2], json.loads(з["ділянка"]))
    п = ЖК.виміряти_поверхню(bgr, маска) if з["тло"] == "біле" else В1.виміряти_без_поправки(bgr, маска)
    слово_моделі = СК.СЛОВО[з["код"]]
    вих = dict(номер=з["номер"], річ=з["річ"], кадр=з["кадр"], тло_моделі=з["тло"],
               поправка=п.get("поправка") or "", множники=json.dumps(п.get("множники")),
               придатна="так" if п["придатна"] else "ні", візерунок_коду=п["візерунок"] or "",
               код_моделі=з["код"], родина_моделі=СК.СІМ_Я[слово_моделі], принт_моделі=з["принт"],
               інші_коди_моделі=з["інші_коди"],
               межі_моделі=json.dumps(межі_моделі(з["код"], з["інші_коди"]), ensure_ascii=False),
               сегменти=" ".join("%s:%.2f:%s" % (СК.КОД.get(с["слово"], с["слово"]), с["частка"], с["hex"])
                                 for с in п["сегменти"]),
               позначки=json.dumps(п["позначки"], ensure_ascii=False))
    if not п["сегменти"]:
        вих.update(стан="невідомо", чому=п["чому"])
        return вих
    с = п["сегменти"][0]
    lab, U = tuple(с["lab"]), с["хрома"][1]
    вміщають = вікна_точки(lab)
    найтісніше, _ = П.слово_з_lab(lab)
    слово = вікно_моделі(вміщають, слово_моделі)
    _, межі, _ = П.код_розкиду(lab, U, п.get("множники"))
    причини = []
    if слово is None:
        причини.append("жодне вікно коду чи родини моделі «%s» не вміщає точку (вміщають: %s)" % (
            вих["родина_моделі"], ", ".join(СК.КОД[сл] for _, сл in вміщають) or "жодне"))
    elif not розкид_у_вікні(lab, U, п.get("множники"), слово):
        причини.append("розкид (L* %.0f–%.0f, C* %.0f–%.0f) поза вікном «%s»" % (
            межі[0], межі[1], межі[2], межі[3], СК.КОД[слово]))
    L, C, h = CS.lch(lab)
    вих.update(hex=с["hex"], lab=json.dumps(с["lab"]), lch="%.1f %.1f %.0f" % (L, C, h), U=U, частка=с["частка"],
               вікна_точки=" ".join(СК.КОД[сл] for _, сл in вміщають),
               код_найтіснішого=СК.КОД[найтісніше],
               код_точки=СК.КОД[слово] if слово else "",
               родина_точки=СК.СІМ_Я[слово] if слово else "",
               межі_виміру=json.dumps(В1.округлити(межі)),
               стан="не певний" if причини else "певний",
               код_після="" if причини else СК.КОД[слово],
               чому="; ".join(причини) if причини else п["чому"])
    return вих


ПОЛЯ = ("номер", "річ", "кадр", "тло_моделі", "поправка", "множники", "придатна", "візерунок_коду", "принт_моделі",
        "код_моделі", "родина_моделі", "інші_коди_моделі", "hex", "lab", "lch", "U", "частка", "вікна_точки",
        "код_найтіснішого", "код_точки", "родина_точки", "межі_виміру", "межі_моделі", "стан", "код_після",
        "сегменти", "позначки", "чому")


def головна():
    вхід = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ТУТ, "модель.tsv")
    вихід = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ТУТ, "вимір.tsv")
    with open(вхід, encoding="utf-8") as ф:
        записи = list(csv.DictReader(ф, delimiter="\t"))
    рядки = [рядок(з) for з in записи]
    with open(вихід, "w", encoding="utf-8", newline="") as ф:
        п = csv.DictWriter(ф, ПОЛЯ, delimiter="\t", lineterminator="\n", extrasaction="raise")
        п.writeheader()
        for р in рядки:
            п.writerow({к: р.get(к, "") for к in ПОЛЯ})
    стани = [р["стан"] for р in рядки]
    print("речей %d: певний %d, не певний %d, невідомо %d" % (
        len(рядки), стани.count("певний"), стани.count("не певний"), стани.count("невідомо")))


if __name__ == "__main__":
    головна()
