# -*- coding: utf-8 -*-
"""Звіт спроби 2 на нових 40 → `звіт.tsv` і таблиця README: річ · кадр · вимір ДО · модель · точка ПІСЛЯ · вердикти.

Вимір ДО — запис кадру в дельті перезбору (гілка даних на голові ДАНІ: hex і код, які річ має зараз), прочитаний
після свідка записів моделі. Вердикти оглядачів — порожні: оглядачів запускає диспетчер.

Запуск із кореня (після `git fetch origin claude/Річ-колір-вимір`):
`python3 -I аудит/проби/річ_колір_модель_бачить/спроба_2/звіт.py` → `звіт.tsv`, таблиця — у stdout.
"""
import csv
import gzip
import json
import os
import subprocess
import sys

ТУТ = os.path.dirname(os.path.abspath(__file__))
КОРІНЬ = os.path.abspath(os.path.join(ТУТ, "..", "..", "..", ".."))
sys.path.insert(0, os.path.join(КОРІНЬ, "джерела"))
import словник_кольору as СК  # noqa: E402

ДАНІ = "43dd34adee5bf462c70cbdc9f01719da7250719e"
ТЕКА_ДАНИХ = "аудит/проби/річ_колір_перезбір_0411/"


def читати(шлях):
    with open(шлях, encoding="utf-8") as ф:
        return {int(р["номер"]): р for р in csv.DictReader(ф, delimiter="\t")}


def вимір_до(ід, кадр, дельта, маніфест):
    """(hex, код) запису кадру в дельті: кадр — фото маніфесту, запис — той самий файл і url."""
    ключі = [(м["файл"], м["url"]) for м in маніфест.get(ід, []) if м["фото"] == кадр]
    записи = [в for в in дельта["записи"][ід] if (в["файл"], в["url"]) in ключі]
    assert len(записи) == 1, (ід, кадр, len(записи))
    в = записи[0]
    код = СК.КОД.get(в["слово"], в["слово"])
    return в["hex"], код


def ділянка_коротко(д):
    п = json.loads(д)
    return "%d прям., рамка %d,%d–%d,%d" % (len(п), min(x[0] for x in п), min(x[1] for x in п),
                                           max(x[2] for x in п), max(x[3] for x in п))


def межі_виміру(м):
    L0, L1, C0, C1, дуга = json.loads(м)
    return "L* %.0f–%.0f, C* %.0f–%.0f, %s" % (L0, L1, C0, C1, "тон %d–%d°" % tuple(дуга) if дуга else "тон будь-який")


def головна():
    модель, вимір, кадри = (читати(os.path.join(ТУТ, ф)) for ф in ("модель.tsv", "вимір.tsv", "кадри.tsv"))
    сирі = subprocess.run(["git", "-C", КОРІНЬ, "show", "%s:%sдельта.json.gz" % (ДАНІ, ТЕКА_ДАНИХ)],
                          check=True, capture_output=True).stdout
    дельта = json.loads(gzip.decompress(сирі))
    маніфест = {}
    for м in дельта["маніфест"]:
        маніфест.setdefault(м["id"], []).append(м)
    рядки = []
    for н in sorted(модель):
        м, в, к = модель[н], вимір[н], кадри[н]
        assert м["річ"] == в["річ"] == к["річ"] and м["кадр"] == в["кадр"] == к["кадр"], н
        hex_до, код_до = вимір_до(м["річ"], м["кадр"], дельта, маніфест)
        не_певний = в["стан"] != "певний"
        рядки.append({
            "номер": н, "річ": м["річ"], "кадр": м["кадр"], "категорія_тип": "%s / %s" % (к["категорія"], к["тип"]),
            "вимір_ДО": "%s · %s (%s)" % (hex_до, код_до, СК.СЛОВО.get(код_до, "?")),
            "модель_ділянка": ділянка_коротко(м["ділянка"]),
            "модель_принт": м["принт"] + (" (" + м["інші_коди"] + ")" if м["інші_коди"] else ""),
            "модель_тло": м["тло"], "модель_родина": "%s · %s" % (м["код"], м["родина"]),
            "точка_ПІСЛЯ": "%s · %s · %s" % (в["hex"], в["код_точки"] or "—", в["родина_точки"] or "—"),
            "стан_ПІСЛЯ": в["стан"],
            "межі_виміру": межі_виміру(в["межі_виміру"]) if не_певний else "",
            "межі_моделі": " + ".join(json.loads(в["межі_моделі"])) if не_певний else "",
            "вердикт_оглядача_1": "", "вердикт_оглядача_2": "",
        })
    with open(os.path.join(ТУТ, "звіт.tsv"), "w", encoding="utf-8", newline="") as ф:
        п = csv.DictWriter(ф, list(рядки[0]), delimiter="\t", lineterminator="\n")
        п.writeheader()
        п.writerows(рядки)
    print("| № | річ | кадр | вимір ДО | модель: ділянка · принт · тло · родина | точка ПІСЛЯ · стан · межі виміру; "
          "межі моделі | вердикти оглядачів |")
    print("|---|---|---|---|---|---|---|")
    for р in рядки:
        стан = "**%s**" % р["стан_ПІСЛЯ"]
        if р["межі_виміру"]:
            стан += " (%s; %s)" % (р["межі_виміру"], р["межі_моделі"])
        print("| %d | %s | %s | %s | %s · принт %s · тло %s · %s | %s · %s |  |" % (
            р["номер"], р["річ"], os.path.basename(р["кадр"])[:8], р["вимір_ДО"], р["модель_ділянка"],
            р["модель_принт"], р["модель_тло"], р["модель_родина"], р["точка_ПІСЛЯ"], стан))
    стани = [р["стан_ПІСЛЯ"] for р in рядки]
    print("певний %d (%s), не певний %d" % (стани.count("певний"),
                                          " ".join(str(р["номер"]) for р in рядки if р["стан_ПІСЛЯ"] == "певний"),
                                          стани.count("не певний")), file=sys.stderr)


if __name__ == "__main__":
    головна()
