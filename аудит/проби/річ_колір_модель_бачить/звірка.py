    вимір = читати(os.path.join(ТУТ, "вимір.tsv"))
    до = читати(os.path.join(ТУТ, "..", "річ_колір_приймання_0811", "приймання.tsv"))
    рядки, збіг, збіг_точки = [], 0, 0
    for н in sorted(модель):
        м, в, д = модель[н], вимір[н], до[н]
        assert м["річ"] == в["річ"] == д["річ"] and м["кадр"] == в["кадр"] == д["кадр"], н
