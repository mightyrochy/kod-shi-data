# -*- coding: utf-8 -*-
"""Код міряє точку в ділянці, яку назвала модель (наряд `Річ-колір-вимір-модель-бачить`).

Вхід — `модель.tsv` (записи моделі, закомічені до виміру: 9192c9c5) і кадри гілки даних
`claude/Річ-колір-вимір` 43dd34ad. Вимір — той самий вимір поверхні, що в жнивах
(`жнива_колір.виміряти_поверхню` → `surface.виміряти`): маска — прямокутники моделі; тло «біле» — та
сама функція жнив без змін (поправка тла діє); тло «не_біле» — те саме масштабування й той самий
`surface.виміряти` з `поправка=False` (функція жнив поправки не вимикає). Продукту й каталогу не міняє.

Точка коду — головний сегмент поверхні (найбільша частка), як і в жнивах; її слово — `surface.слово_з_lab`,
код і родина — `словник_кольору`. Стан:
- «певний» — родина точки = родина моделі, і весь розкид точки лежить у вікні її коду (`код_розкиду`);
- «не певний» — родина точки ≠ родина моделі (рішення 08.11 12:26) і/або розкид поза вікном коду точки
  (слово власника 08.11 10:07); межі виміру — [L0, L1, C0, C1, дуга] з `код_розкиду`;
- «невідомо» — поверхня непридатна (виміру точки нема), причина — `чому` виміру.

Запуск із кореня репозиторію: `git fetch origin claude/Річ-колір-вимір`, потім
`python3 -I аудит/проби/річ_колір_модель_бачить/вимір.py` → `вимір.tsv` поруч. Потрібні numpy й opencv.
"""
import csv
import json
import os
import subprocess
import sys

КОРІНЬ = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
sys.path.insert(0, os.path.join(КОРІНЬ, "джерела"))

import cv2  # noqa: E402
import numpy as np  # noqa: E402
import surface as П  # noqa: E402
import жнива_колір as ЖК  # noqa: E402
import словник_кольору as СК  # noqa: E402
import colorspace as CS  # noqa: E402

ДАНІ = "43dd34adee5bf462c70cbdc9f01719da7250719e"
ТЕКА_ДАНИХ = "аудит/проби/річ_колір_перезбір_0411/"
ТУТ = os.path.dirname(os.path.abspath(__file__))


def кадр(шлях):
    """BGR кадру з гілки даних (байти git → cv2, як читають жнива)."""
    байти = subprocess.run(["git", "-C", КОРІНЬ, "show", ДАНІ + ":" + ТЕКА_ДАНИХ + шлях],
                           check=True, capture_output=True).stdout
    return cv2.imdecode(np.frombuffer(байти, np.uint8), cv2.IMREAD_COLOR)


def маска_ділянки(h, w, ділянка):
    """Маска 0/255 з прямокутників моделі [x0, y0, x1, y1] у пікселях оригіналу."""
    м = np.zeros((h, w), np.uint8)
    for x0, y0, x1, y1 in ділянка:
        м[max(0, y0):min(h, y1), max(0, x0):min(w, x1)] = 255
    return м


def виміряти_без_поправки(bgr, маска, сід=П.ТИПОВИЙ_СІД):
    """`жнива_колір.виміряти_поверхню` без арр і джерела, але з `поправка=False` — рядок у рядок."""
    h, w = bgr.shape[:2]
    к = min(1.0, П.ДОВГА_СТОРОНА / max(h, w))
    if к < 1:
        розмір = (max(1, round(w*к)), max(1, round(h*к)))
        bgr = cv2.resize(bgr, розмір, interpolation=cv2.INTER_AREA)
        маска = cv2.resize(маска, розмір, interpolation=cv2.INTER_NEAREST)
        h, w = bgr.shape[:2]
    байти = bgr[:, :, ::-1].tobytes()
    rgb = list(zip(байти[::3], байти[1::3], байти[2::3]))
    м = (маска > 127).tobytes()
    return П.виміряти(rgb, w, h, м, клас_маски="ATR", мітки_шкіри=None, сід=сід, поправка=False)


def округлити(межі):
    """Межі розкиду для запису: числа до десятої, дуга — до градуса."""
    L0, L1, C0, C1, дуга = межі
    return [round(L0, 1), round(L1, 1), round(C0, 1), round(C1, 1),
            [round(дуга[0]), round(дуга[1])] if дуга else None]


def рядок(з):
    """Запис моделі → рядок виміру."""
    bgr = кадр(з["кадр"])
    ділянка = json.loads(з["ділянка"])
    маска = маска_ділянки(*bgr.shape[:2], ділянка)
    біле = з["тло"] == "біле"
    п = ЖК.виміряти_поверхню(bgr, маска) if біле else виміряти_без_поправки(bgr, маска)
    вих = dict(номер=з["номер"], річ=з["річ"], кадр=з["кадр"], тло_моделі=з["тло"],
               поправка=п.get("поправка") or "", множники=json.dumps(п.get("множники")),
               придатна="так" if п["придатна"] else "ні", візерунок_коду=п["візерунок"] or "",
               позначки=json.dumps(п["позначки"], ensure_ascii=False),
               сегменти=" ".join("%s:%.2f:%s" % (СК.КОД.get(с["слово"], с["слово"]), с["частка"], с["hex"])
                                 for с in п["сегменти"]),
               код_моделі=з["код"], родина_моделі=з["родина"], принт_моделі=з["принт"])
    if not п["сегменти"]:
        вих.update(стан="невідомо", чому=п["чому"])
        return вих
    с = п["сегменти"][0]
    слово, у_вікні = П.слово_з_lab(tuple(с["lab"]))
    код_р, межі, чому_р = П.код_розкиду(tuple(с["lab"]), с["хрома"][1], п.get("множники"))
    родина = СК.СІМ_Я[слово]
    причини = []
    if родина != з["родина"]:
        причини.append("родина точки «%s» ≠ родина моделі «%s»" % (родина, з["родина"]))
    if код_р is None:
        причини.append(чому_р)
    L, C, h = CS.lch(tuple(с["lab"]))
    вих.update(hex=с["hex"], lab=json.dumps(с["lab"]), lch="%.1f %.1f %.0f" % (L, C, h), U=с["хрома"][1],
               частка=с["частка"], код_точки=СК.КОД[слово], родина_точки=родина,
               у_вікні="так" if у_вікні else "ні", розкид_у_вікні="так" if код_р else "ні",
               межі=json.dumps(округлити(межі)),
               стан="не певний" if причини else "певний",
               код_після="" if причини else СК.КОД[слово],
               чому="; ".join(причини) if причини else п["чому"])
    return вих


ПОЛЯ = ("номер", "річ", "кадр", "тло_моделі", "поправка", "множники", "придатна", "візерунок_коду", "принт_моделі",
        "код_моделі", "родина_моделі", "hex", "lab", "lch", "U", "частка", "код_точки", "родина_точки", "у_вікні",
        "розкид_у_вікні", "межі", "стан", "код_після", "сегменти", "позначки", "чому")


def головна():
    with open(os.path.join(ТУТ, "модель.tsv"), encoding="utf-8") as ф:
        записи = list(csv.DictReader(ф, delimiter="\t"))
    рядки = [рядок(з) for з in записи]
    with open(os.path.join(ТУТ, "вимір.tsv"), "w", encoding="utf-8", newline="") as ф:
        п = csv.DictWriter(ф, ПОЛЯ, delimiter="\t", lineterminator="\n", extrasaction="raise")
        п.writeheader()
        for р in рядки:
            п.writerow({к: р.get(к, "") for к in ПОЛЯ})
    стани = [р["стан"] for р in рядки]
    print("речей %d: певний %d, не певний %d, невідомо %d" % (
        len(рядки), стани.count("певний"), стани.count("не певний"), стани.count("невідомо")))


if __name__ == "__main__":
    головна()
