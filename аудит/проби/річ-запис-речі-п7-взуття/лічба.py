# -*- coding: utf-8 -*-
"""Річ-запис-речі, п.7: ознаки взуття (каблук, підошва, сезон) — що каже картка крамниці і що доходить до рядка
моделі-стилістки. Повний каталог продукту (`каталог_повний.xml.gz`), уся взуттєва річ, не вибірка.

Лише лічба, продукт і каталог не міняються. Рядок моделі — той самий шлях, що в `пакет_моделі` (рядки 1558–1596):
`композитор_річ.у_річ`/`graph.зона` → `дріт_моделі.осі` з тими самими входами (`каблук.каблук` за назвою й url, як
`міст_пакет.py:1785`, поле `каблук` фіду). Словники нижче — ПРИЛАД ЛІЧБИ (щоб порахувати слова в назві й картці), а не
пропозиція для продукту (паспорт, п.7).

Запуск: python3 аудит/проби/річ-запис-речі-п7-взуття/лічба.py [кеш.pkl]   (завантаження каталогу ~2–3 хв; кеш — pickle)
Вихід: `числа.json` поруч, і стисла таблиця в stdout."""
import collections, gzip, json, os, pickle, re, sys, warnings

КОРІНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
ТУТ = os.path.dirname(os.path.abspath(__file__))
warnings.simplefilter("ignore")
sys.path.insert(0, os.path.join(КОРІНЬ, "джерела")); os.chdir(os.path.join(КОРІНЬ, "джерела"))
import фід_каталог as ФК, дріт_моделі as Д, graph as ГР, каблук as КБ  # noqa: E402

кеш = sys.argv[1] if len(sys.argv) > 1 else None
if кеш and os.path.exists(кеш):
    каталог = pickle.load(open(кеш, "rb"))
else:
    каталог = ФК.прочитати_каталог(ФК.каталог_на_диску(), ліміт_фото=0)["каталог"]
    if кеш:
        pickle.dump(каталог, open(кеш, "wb"))
взуття = [r for r in каталог if r.get("слот") == "взуття"]

# ── картка крамниці: назва, param-и, опис з XML (те, що крамниця сказала словами) ──
xml = gzip.open(os.path.join(КОРІНЬ, "каталог_повний.xml.gz"), "rt", encoding="utf-8").read()
картки = {}
for м in re.finditer(r'<offer id="([^"]+)"[^>]*>(.*?)</offer>', xml, re.S):
    т = м.group(2)
    if '<param name="слот">взуття</param>' not in т:
        continue
    пар = {a: b for a, b in re.findall(r'<param name="([^"]*)">(.*?)</param>', т, re.S)}
    картки[м.group(1)] = dict(пар=пар)
# ПРИЛАД: стеблини слів, що ми ЛІЧИМО в назві й картці (не продукт)
_ВИД = r"шпильк|стилет|танкет|платформ|блочн|кітен|kitten"   # вид каблука
_ПРИСУТН = r"на підбор|на каблук"                                   # каблук є, виду не каже
_ПІД = r"підошв|тракторн|ребрист|протектор"
_СЕЗ = r"зимов|демісезон|осінн|весн|літн|утеплен|хутр|флісі|на флісі|зима|осінь|весна|літо"
поле_каблук_висота = re.compile(r"(?i)висот\w*\s+(підбор|каблук)")
поле_каблук_вид = re.compile(r"(?i)(вид|тип|форма)\s+(каблук|підбор)")
поле_підошва = re.compile(r"(?i)(підошв|подошв)")
поле_сезон = re.compile(r"(?i)(^|[~\s])сезон")


def слова_картки(ід):
    """Ознаки у param-ах і в тексті `опис` картки: (висота каблука, вид каблука, підошва, сезон) — є/нема."""
    пар = (картки.get(ід) or {}).get("пар") or {}
    ключі = " | ".join(str(к).lstrip("~") for к in пар)
    опис = str(пар.get("опис") or "")
    тут = ключі + " | " + опис
    return dict(висота=bool(поле_каблук_висота.search(тут)), вид=bool(поле_каблук_вид.search(тут)),
                підошва=bool(поле_підошва.search(ключі) or re.search(r"(?i)підошва\s", опис)),
                сезон=bool(re.search(r"(?i)(^|\|)\s*~?сезон|\bСезон\s", тут)))


лічильник, приклади = collections.Counter(), collections.defaultdict(list)
рядки = []
for r in взуття:
    ід = r["id"].split("@")[0]
    кб = КБ.каблук(r["назва"], None, r.get("url"))
    рч = dict(r, слот="взуття")
    о = Д.осі(ГР.зона(рч), dict(рч, каблук_є=кб["є"], каблук=r.get("каблук"), каблук_форма=кб["форма"],
                              каблук_висота=кб["висота"], каблук_словами=КБ.словами(кб)))
    н = (r["назва"] or "").lower()
    к = слова_картки(ід)
    рядок = dict(id=r["id"], назва=r["назва"], тип=r.get("тип"), heel=о.get("heel"), heel_shape=о.get("heel_shape"),
                 heel_height=о.get("heel_height"), fabric_bands=о.get("fabric_bands"),
                 каблук_фід=r.get("каблук"), каблук_см=r.get("каблук_см"), клас=r.get("каблук_клас"),
                 підошва_фід=r.get("підошва"), сезон_тканини=r.get("сезон_тканини"),
                 регекс_назва_є=кб["є"], картка=к,
                 назва_вид=bool(re.search(_ВИД, н)), назва_підошва=bool(re.search(_ПІД, н)), назва_присутн=bool(re.search(_ПРИСУТН, н)),
                 назва_сезон=bool(re.search(_СЕЗ, н)))
    рядки.append(рядок)
Н = len(рядки)
ч = лічильник
ч["пар"] = Н
ч["…із них картка знайдена в XML за id"] = sum(1 for r in взуття if r["id"].split("@")[0] in картки)
for р in рядки:
    ч["heel:" + str(р["heel"])] += 1
    ч["heel_shape у рядку"] += bool(р["heel_shape"])
    ч["heel_height у рядку"] += bool(р["heel_height"])
    ч["fabric_bands у рядку"] += bool(р["fabric_bands"])
    # (3а) лише heel yes/unknown
    if р["heel"] in ("yes", "unknown"):
        ч["heel yes|unknown"] += 1
        ч["…із них без висоти й без виду в рядку"] += not (р["heel_shape"] or р["heel_height"])
    if р["heel"] == "yes":
        рег, фід = р["регекс_назва_є"] is True, р["каблук_фід"] is True
        ч["heel=yes: свідок лише фід (поле/текст картки, `фід_взуття`)"] += фід and not рег
        ч["heel=yes: свідок лише слово в назві/url (`каблук.каблук`)"] += рег and not фід
        ч["heel=yes: обидва свідки"] += рег and фід
    ч["фід: каблук_см є"] += р["каблук_см"] is not None
    ч["фід: каблук_см > 0"] += (р["каблук_см"] or 0) > 0
    ч["фід: клас каблука"] += р["клас"] is not None
    ч["фід: число або клас висоти"] += (р["каблук_см"] is not None or р["клас"] is not None)
    ч["фід: підошва"] += р["підошва_фід"] is not None
    ч["фід: сезон_тканини"] += р["сезон_тканини"] is not None
    # утрата на дроті: фід має, рядок не має
    ч["ВТРАТА висота: фід має (число/клас), рядок без heel_height"] += (
        (р["каблук_см"] or 0) > 0 or р["клас"] is not None) and not р["heel_height"]
    ч["ВТРАТА підошва: фід має, рядка нема"] += р["підошва_фід"] is not None
    ч["ВТРАТА сезон: фід має сезон_тканини, у рядку лише fabric_bands"] += (
        р["сезон_тканини"] is not None and not р["fabric_bands"])
    ч["ВТРАТА fabric_bands не з сезону тканини (у рядку є без фіду)"] += bool(р["fabric_bands"]) and р["сезон_тканини"] is None
    # картка словами (param/опис)
    for ім in ("висота", "вид", "підошва", "сезон"):
        ч["картка: є поле «%s»" % ім] += р["картка"][ім]
    ч["картка: висота каблука, рядок без heel_height"] += р["картка"]["висота"] and not р["heel_height"]
    ч["картка: вид каблука, рядок без heel_shape"] += р["картка"]["вид"] and not р["heel_shape"]
    ч["картка: підошва, у рядку підошви нема ніколи"] += р["картка"]["підошва"]
    ч["картка: сезон, рядок без сезону"] += р["картка"]["сезон"] and not р["fabric_bands"]
    # (3в) назви
    ч["назва: слово виду каблука"] += р["назва_вид"]
    ч["назва: слово виду каблука, рядок без heel_shape"] += р["назва_вид"] and not р["heel_shape"]
    ч["назва: «на підборах/на каблуку» (каблук є, виду нема)"] += р["назва_присутн"]
    ч["назва: слово підошви"] += р["назва_підошва"]
    ч["назва: слово сезону"] += р["назва_сезон"]
    ч["назва: слово сезону, рядок без fabric_bands"] += р["назва_сезон"] and not р["fabric_bands"]
for р in рядки:
    if р["підошва_фід"] == "теп":
        ч["підошва=«теп»: у фіді"] += 1
        пар = (картки.get(р["id"].split("@")[0]) or {}).get("пар") or {}
        текст = (р["назва"] + " " + " ".join(str(v) for v in пар.values())).lower()
        ч["підошва=«теп»: у тексті є слово «теплий/утеплений/тепла» (а не ТЕП)"] += bool(re.search(r"тепл|утепл", текст))
        ч["підошва=«теп»: у тексті є окреме «тер/тep» (TPR/ТЕП)"] += bool(re.search(r"(^|[^а-яіїєґa-z])т[еe]п([^а-яіїєґa-z]|$)|tpr", текст))
# уггі vs шпильки: однаковий рядок
уг = [р for р in рядки if re.search(r"уг[гґ]|ugg", (р["назва"] or "").lower()) or р["тип"] == "уггі"]
шп = [р for р in рядки if re.search(r"шпильк", (р["назва"] or "").lower())]
ч["уггі (тип/назва)"] = len(уг)
ч["уггі з heel=yes"] = sum(р["heel"] == "yes" for р in уг)
ч["уггі з каблук_см>0 у фіді"] = sum((р["каблук_см"] or 0) > 0 for р in уг)
ч["шпильки за назвою"] = len(шп)
ч["шпильки з heel=yes"] = sum(р["heel"] == "yes" for р in шп)
ч["шпильки з heel_height у рядку"] = sum(bool(р["heel_height"]) for р in шп)
# однакове значення «каблука» на дроті в уггів і в пар з каблуком ≥ 10 см у фіді
високі = [р for р in рядки if (р["каблук_см"] or 0) >= 10]
ч["фід: каблук ≥ 10 см"] = len(високі)
ч["…із них heel=yes без shape/height"] = sum(р["heel"] == "yes" and not (р["heel_shape"] or р["heel_height"]) for р in високі)
низькі_уг = [р for р in уг if (р["каблук_см"] or 0) and р["каблук_см"] <= 3]
ч["уггі з каблук_см ≤ 3 у фіді"] = len(низькі_уг)
ч["…із них heel=yes (той самий рядок, що в ≥10 см)"] = sum(р["heel"] == "yes" for р in низькі_уг)
# приклади для звіту
def з(список, к=5):
    return [dict(id=р["id"], назва=р["назва"], heel=р["heel"], каблук_см=р["каблук_см"], клас=р["клас"], підошва=р["підошва_фід"])
            for р in список[:к]]
приклади["уггі heel=yes, фід каблук_см"] = з([р for р in уг if (р["каблук_см"] or 0) > 0])
приклади["високий каблук у фіді, у рядку лише heel=yes"] = з([р for р in високі if not (р["heel_shape"] or р["heel_height"])])
приклади["назва зі словом виду, у рядку без heel_shape"] = з([р for р in рядки if р["назва_вид"] and not р["heel_shape"]])
приклади["підошва у фіді"] = з([р for р in рядки if р["підошва_фід"]])
приклади["назва зі словом сезону без сезону в рядку"] = з([р for р in рядки if р["назва_сезон"] and not р["fabric_bands"]])
вихід = dict(числа=dict(ч), приклади={к: v for к, v in приклади.items()})
json.dump(вихід, open(os.path.join(ТУТ, "числа.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
for к, v in ч.items():
    print("%-70s %s" % (к, v))
for к, v in приклади.items():
    print("\n#", к); [print("  ", x) for x in v[:5]]
