"""Порівнює суд без входу й з виміряним нулем та проходження питання ланцюгом."""
import importlib
import json
import subprocess
import sys
import types
from pathlib import Path

sys.path.insert(0, str(Path("джерела").resolve()))
from вхід_правила import нема_входу, брак
import знахідка
import суд_чеклісти


def модуль(ім, база=None):
    """Читає поточну реалізацію або точний код ДО з коміту."""
    if база is None:
        return importlib.import_module(ім)
    текст = subprocess.check_output(["git", "show", f"{база}:джерела/{ім}.py"]).decode("utf-8")
    м = types.ModuleType(ім + "_до")
    exec(compile(текст, ім + "_до.py", "exec"), м.__dict__)
    return м


def вимір(база=None):
    """Судить однакові речі: поля нема, поле None, поле з виміряним нулем."""
    вих = {}
    for ім, функція, поле in (("суд_блиск", "блиск_бюджет", "блиск"),
                              ("суд_ремесло", "фокуси", "площа")):
        судити = getattr(модуль(ім, база), функція)
        випадки = {}
        for стан, значення in (("відсутнє", {}), ("None", {поле: None}), ("нуль", {поле: 0})):
            речі = [dict(річ="ф1", слот="верх", **значення)]
            з = судити(речі)
            випадки[стан] = dict(питань=sum(нема_входу(x) for x in з), знахідок=len(з))
        вих[функція] = випадки
    return вих


if __name__ == "__main__":
    до = вимір(sys.argv[1]) if len(sys.argv) > 1 else None
    після = вимір()
    for в in після.values():
        assert в["відсутнє"]["питань"] == в["None"]["питань"] == 1
        assert в["нуль"]["питань"] == 0
    з = брак("K-MAT-04", [dict(річ="ф1")], ("блиск",))
    пари = знахідка.усі({"суд": [з]})
    assert len(пари) == len(знахідка.припущення(пари)) == 1
    assert з["сила_нп"] == 0 and not з["блокує"]
    ч = суд_чеклісти.позначити_без_входу({"надлишок": [dict(пункт=1,
        правила=["K-MAT-04"], стан="пройдено")]}, [з])
    assert ч["надлишок"][0]["стан"] == "без входу"
    утримано = dict(правило="K-FIT-01", сила="утримано", суть="checked",
                    чому="checked_no_conclusion", сила_нп=None)
    знахідка.усі([утримано])
    assert not нема_входу(утримано) and утримано["сила"] == "утримано"
    метали = модуль("суд_блиск").метали([dict(річ="ф1", слот="сережки",
        метал="золото", near=0.8, площа=None)], {})
    assert [п["без_входу"] for п in метали] == ["rule_input_missing"]
    assert [д["field"] for п in метали for д in п["бракує"]] == ["площа"]
    сегментація = модуль("суд_огляд").перевірка_сегментації({"очі": dict(L=40, a=None, b=2)}, [])
    assert [д["field"] for п in сегментація for д in п["бракує"]] == ["a"]
    import accessory, outer, суд_образу
    assert {accessory.сезон_і_погода.__module__, outer.теплові_знахідки.__module__,
            суд_образу.погода.__module__} == {"суд_погода"}
    print(json.dumps(dict(ДО=до, ПІСЛЯ=після, ланцюг="питання → припущення → без входу",
        погодних_власників=1, утримання_після_перевірки="збережено"), ensure_ascii=False, indent=2))
