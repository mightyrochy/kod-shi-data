#!/usr/bin/env python3
"""сN_*/розбіжності.md: кожен крок `хід.md` третього прогону, що не ліг на новий екран (номер кроку, що мало бути, що було).
Запуск (з теки стенд/): python3 розбіжності_md.py <ситуація> — доповнює файл, який повтор.js пише по ходу (рядки «крок N …»), підсумком із підсумок.json."""
import json, os, re, sys, collections
с = sys.argv[1]
тека = os.path.join('..', с)
п = json.load(open(os.path.join(тека, 'підсумок.json'), encoding='utf8'))
ф = os.path.join(тека, 'розбіжності.md')
рядки = open(ф, encoding='utf8').read().strip() if os.path.exists(ф) else ''
вид = collections.Counter()
for к in п['кроки']:
    д = к['дія']
    вид['надрукувала' if д.startswith('надрукувала') else 'натиснула' if д.startswith('натиснула') else 'гортнула' if д.startswith('гортнула') else 'чекала' if д.startswith('чекала') else 'готово' if д == 'готово' else 'інше'] += 1
не = [к for к in п['кроки'] if not к['лягло']]
шапка = f"""# Розбіжності — {с}: кроки `хід.md` третього прогону, що не ліг на новий екран

Скрипт-жінка пройшов кроки `аудит/проби/живий-як-людина-3/{с}/хід.md` рядок за рядком (дія з рядка «- дія:»); крок «ліг», коли записаний елемент (за підписом) був на екрані й дія виконалась, і не ліг — коли елемента не було чи дія впала.

- кроків у `хід.md` третього прогону: {п['кроків_джерела']}
- лягло: {п['кроків_лягло']}
- не лягло: {len(не)}
- склад кроків: {', '.join(f'{к} — {в}' for к, в in вид.items())}; «гортнула» і «чекала» не залежать від екрана — скрипт виконує їх завжди (чекання — до спокою сторінки, а не на записані секунди)
- слів надруковано: {п['слів_лягло']} з {п['слів_лягло'] + п['слів_пропущено']}; проходів (натискань «Новий» + 1): {п['проходів']}
- точність збігу підписів — `звірка_кроків.md` (кожен підпис тапу чи введення був на екрані точно таким, яким записаний, чи за початком)
"""
if не:
    шапка += "\n## Кроки, що не лягли\n\n" + "\n".join(f"- крок {к['крок']} (прохід {к['прохід']}) · мало бути: {к['дія']} · було: {к.get('чому')}" for к in не) + "\n\nПодробиці (що було на екрані й які елементи були) — рядки нижче, які повтор.js записав по ходу:\n\n" + рядки + "\n"
else:
    шапка += "\n## Кроки, що не лягли\n\nНема: кожен із кроків знайшов елемент і виконався; рядків «крок N … мало бути … було» повтор.js не писав.\n"
open(ф, 'w', encoding='utf8').write(шапка)
print(шапка[:600])
