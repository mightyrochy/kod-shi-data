#!/usr/bin/env python3
"""Як записані кроки лягли на екран (наряд Живий-як-людина-4, мірило 2): для кожного кроку `хід.md` третього прогону з тапом чи
введенням — чи був на екрані елемент із точно тим самим підписом (а не лише за початком підпису чи за першими словами рядка картки
сценарію). Дані: службове/<с>/екрани.jsonl (кожен кадр: крок, опис, елем) і підсумок.json. Запуск (з теки стенд/):
python3 звірка_кроків.py <ситуація> > ../<ситуація>/звірка_кроків.md"""
import json, re, sys, os
с = sys.argv[1]
тека = os.path.join('..', с); служб = os.path.join('службове', с)
підсумок = json.load(open(os.path.join(тека, 'підсумок.json'), encoding='utf8'))
кадри = [json.loads(л) for л in open(os.path.join(служб, 'екрани.jsonl'), encoding='utf8')]
def норм(т): return re.sub(r'\s+', ' ', re.sub(r' · зараз:.*$', '', re.sub(r'^\[\d+\] ', '', т))).strip()
# межі кроків джерела в послідовності кадрів
поч = []
for н, к in enumerate(кадри):
    м_ = re.match(r'джерело, крок (\d+):', к['опис'])
    if м_: поч.append((н, int(м_.group(1))))
діапазон = {}
for і, (н, кр) in enumerate(поч):
    діапазон[кр] = (н, поч[і + 1][0] if і + 1 < len(поч) else len(кадри))
рядки = []; лічба = {'точно': 0, 'за початком підпису': 0, 'не знайдено': 0, 'інші дії (гортання, очікування, кінець)': 0}
for к in підсумок['кроки']:
    м = re.match(r'(надрукувала в|натиснула) «([^»]*)»', к['дія'])
    if not м:
        лічба['інші дії (гортання, очікування, кінець)'] += 1; continue
    мітка = м.group(2)
    н0, н1 = діапазон.get(к['крок'], (0, 0))
    точно = False; префікс = False
    for кадр in кадри[н0:н1]:
        for ел in кадр['елем']:
            a, b = норм(ел), норм(мітка)
            if a == b: точно = True
            elif a.startswith(b) or b.startswith(a): префікс = True
    стан = 'точно' if точно else 'за початком підпису' if префікс else 'не знайдено'
    лічба[стан] += 1
    if стан != 'точно': рядки.append(f"| {к['крок']} | прохід {к['прохід']} | {мітка[:110]} | {стан} | {'ліг' if к['лягло'] else 'не ліг'} |")
print(f"# Звірка підписів кроків — {с}\n")
print("Кроки `хід.md` третього прогону з тапом чи введенням: чи був на екрані (у кадрах від цього кроку до наступного) елемент із **точно тим самим** підписом. Підпис за початком — елемент, чий підпис починається з записаного (чи навпаки; кнопка сценарію зі зміненим значенням).\n")
for к, в in лічба.items(): print(f"- {к}: {в}")
print("\n| крок джерела | прохід | записаний підпис | на екрані | результат |\n|---|---|---|---|---|")
print("\n".join(рядки) if рядки else "| — | — | усі кроки з тапом чи введенням знайшли елемент із тим самим підписом | — | — |")
