def повідомлення(тип, вміст, кінець=None):
    """Складає запис формату транскрипту Claude."""
    return {'type': тип, 'message': {'content': вміст, 'stop_reason': кінець}}


def вхід(рядок):
    """Складає звичайний user-запис, зокрема лист, доставлений посеред ходу."""
    return повідомлення('user', [{'type': 'text', 'text': рядок}])


def дія(аргументи, назва='Bash', номер='дія'):
    """Складає виклик інструмента з аргументами, які справді бачить хук."""
    return повідомлення('assistant', [{'type': 'tool_use', 'id': номер, 'name': назва, 'input': аргументи}], 'tool_use')


def результат(вміст, номер='дія'):
    """Складає tool_result, який не повинен ставати новим входом збою."""
    return повідомлення('user', [{'type': 'tool_result', 'tool_use_id': номер, 'content': вміст}])


def кінець(рядок='—'):
    """Закриває хід окремим записом end_turn."""
    return повідомлення('assistant', [{'type': 'text', 'text': рядок}], 'end_turn')


def записати(шлях, записи):
    """Пише штучний транскрипт у UTF-8."""
    шлях.write_text('\n'.join(json.dumps(з, ensure_ascii=False) for з in записи), encoding='utf-8')


def вимір(тека, модуль):
    """Лічить завершені ходи, збої та повернення за кожним предметом."""
    шляхи = [тека] if тека.is_file() else sorted(тека.rglob('*.jsonl'))
    if not шляхи:
        raise ValueError(f'немає транскриптів: {тека}')
    кінці = зі_збоєм = повернув = 0
    предмети, без_кроку = Counter(), Counter()
    for шлях in шляхи:
        for хід in модуль.ходи(шлях):
            if not хід['завершено']:
                continue
            кінці += 1
            зі_збоєм += bool(хід['збої'])
            повернув += bool(хід['без_кроку'])
            предмети.update({з['предмет'] for з in хід['збої']})
            без_кроку.update({з['предмет'] for з in хід['без_кроку']})
    print(f'кінці: {кінці}; зі збоєм: {зі_збоєм}; повернув би хук: {повернув}')
    for предмет in sorted(предмети):
        print(f'{предмет}: зі збоєм {предмети[предмет]}; без кроку {без_кроку[предмет]}')
    return кінці, зі_збоєм, повернув, предмети, без_кроку


