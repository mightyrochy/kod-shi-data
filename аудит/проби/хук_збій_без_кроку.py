def main():
    """Вибирає штучну пробу або вимір теки справжніх транскриптів."""
    sys.stdout.reconfigure(encoding='utf-8')
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument('тека', nargs='?', type=Path)
    аргументи = парсер.parse_args()
    опис = importlib.util.spec_from_file_location('хук', ХУК)
    модуль = importlib.util.module_from_spec(опис)
    опис.loader.exec_module(модуль)
    if аргументи.тека:
        вимір(аргументи.тека, модуль)
        return 0
    return проба(ХУК, модуль)


if __name__ == '__main__':
    sys.exit(main())
