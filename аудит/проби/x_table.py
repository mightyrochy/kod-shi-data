# -*- coding: utf-8 -*-
"""x_table.py — таблиця воріт: ЩО ЗАЯВЛЕНО «гейт» і ЧИ Є ПІД НИМ ДОКАЗОВА БАЗА.

Проба Н-V23-046. Після Н-02-05 регістр знахідки вирішує ОДНА таблиця —
`реєстр_політика.ПОЛІТИКА_РЕГІСТРУ`, а не карта `РЕГІСТР_ПРАВИЛА` у кожному модулі.
Кожен рядок — правило з регістром «гейт». Колонка `тір` — найслабший тір константи
реєстрів ядра, accessory, outer і fit, що голосує за це правило
(`реєстр_тіри._тір_правила`); `тір=None` — під правилом НЕ оголошено жодної
константи. Колонка «гейт?» питає САМУ машинерію (`реєстр_тіри.регістр`).

ПРИЙМАННЯ: гейт із підставою «фізика речі» (доказ — вимір) має тір АБО корпусну силу
hard/strong з названим джерелом (так стоїть K-WEA-01: `hard` на вході, тіру нема);
«межа людини» доказується словом жінки, тіру не потребує.
"""
# Кличеться з теки `джерела`:  PYTHONPATH=. python3 ../аудит/проби/x_table.py
import sys

import реєстр_політика as ПОЛ
import реєстр_тіри as ТІР
import accessory as A
import outer as OU
import fit as F

РЕЄСТРИ = [ТІР.REGISTRY, A.РЕЄСТР, OU.РЕЄСТР, F.РЕЄСТР]
ПОРЯДОК = ("T3", "T2", "T1")        # від найслабшого


def тір(правило):
    """Найслабший тір серед реєстрів, де правило має константи; None — нема жодної."""
    т = [x for x in (ТІР._тір_правила(правило, р) for р in РЕЄСТРИ) if x]
    return min(т, key=ПОРЯДОК.index) if т else None


def гейт(правило):
    """Чи видає машинерія гейт на найсильнішу емісію (reg — реєстр, де правило голосує)."""
    for р in РЕЄСТРИ:
        if ТІР._тір_правила(правило, р) is not None:
            return any(ТІР.регістр(правило, с, р) == "гейт" for с in ("hard", "strong"))
    return any(ТІР.регістр(правило, с) == "гейт" for с in ("hard", "strong"))


рядки = [(к, v.get("підстава"), v.get("сила_корпусу"), тір(к), гейт(к))
         for к, v in sorted(ПОЛ.ПОЛІТИКА_РЕГІСТРУ.items()) if v.get("регістр") == "гейт"]
ш = "%-10s %-14s %-8s %-6s %s"
print(ш % ("правило", "підстава", "корпус", "тір", "гейт?"))
print("─" * 60)
for р in рядки:
    print(ш % (р[0], р[1], р[2], р[3], "так" if р[4] else "ні"))
биті = [р for р in рядки if р[1] == ПОЛ.ФІЗИКА_РЕЧІ and р[3] is None
        and not (р[2] in ("hard", "strong") and ПОЛ._політика(р[0]).get("джерело"))]
print("─" * 60)
print("гейтів: %d; фізика речі без тіру й без корпусного джерела: %d" % (len(рядки), len(биті)))
for р in биті:
    print("  ✗ %s — фізика речі, а доказу (тір чи корпус) нема" % р[0])
sys.exit(1 if биті else 0)
