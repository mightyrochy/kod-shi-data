"""x_table.py — таблиця воріт: ЩО ЗАЯВЛЕНО «гейт» і ЧИ Є ПІД НИМ ДОКАЗОВА БАЗА.

Проба Н-V23-046. Кожен рядок — правило, якому карта регістру свого модуля дає
«гейт». Колонка `тір` — найслабший тір константи реєстру, що голосує за це
правило (`outfit._тір_правила`); `тір=None` означає, що під правилом НЕ оголошено
ЖОДНОЇ константи. Колонка «гейт?» питає САМУ машинерію (`outfit.регістр`), а не
копію її логіки: «так, якщо емісія дає hard/strong» — коли гейт буде виданий.

ПРИЙМАННЯ: жоден рядок не має водночас `тір=None` і «так, якщо емісія дає …».
"""
# ЗВІДКИ ЦЕЙ ФАЙЛ. Приймальні команди Н-V23-046, Н-V23-047 і Н-V23-048
# кличуть `$SCRATCH/x_table.py` — пробу, написану під час перевірки V23 і
# втрачену разом зі скретчем тієї сесії. Відтворено за дослівним описом
# приймання (сесія С-29) і покладено в репозиторій, щоб наступні дві сесії
# не відтворювали її втретє. Кличеться з теки `джерела`:
#   cd джерела && PYTHONPATH=. python3 ../аудит/проби/x_table.py
import sys

import accessory as A
import outer as OU
import fit as F

import реєстр_політика as RP
import реєстр_тіри as RT

ТАК = "так, якщо емісія дає hard/strong"

рядки = []
for правило, політика in sorted(RP.ПОЛІТИКА_РЕГІСТРУ.items()):
    if політика.get("регістр") != "гейт":
        continue
    тір = політика.get("підстава")
    стеля = політика.get("сила_корпусу")
    доказ = тір and політика.get("джерело")
    рядки.append(("політика", правило, тір, стеля,
                  ТАК if доказ else "ні: доказової підстави нема"))

ш = "%-10s %-12s %-6s %-8s %s"
print(ш % ("модуль", "правило", "тір", "стеля", "гейт?"))
print("─" * 92)
for р in рядки:
    print(ш % (р[0], р[1], str(р[2]), str(р[3]), р[4]))

биті = [р for р in рядки if р[2] is None and р[4] == ТАК]
print("─" * 92)
print("рядків: %d; гейт без тіру: %d" % (len(рядки), len(биті)))
for р in биті:
    print("  ✗ %s.%s — тір=None, а гейт усе одно видається" % (р[0], р[1]))
sys.exit(1 if биті else 0)
