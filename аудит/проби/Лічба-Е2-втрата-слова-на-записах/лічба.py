ВІКНО = 25


def блоки(А, Б):
    """Відрізки виконання А (зі значенням), яких нема в Б (без нього): спільний початок, розбіжність, знову спільне
    (вікно ВІКНО рядків). [(початок, кінець)] у А."""
    індекс = collections.defaultdict(list)
    for п in range(len(А) - ВІКНО + 1):
        індекс[tuple(А[п:п + ВІКНО])].append(п)
    вих, і, й = [], 0, 0
    while і < len(А) and й < len(Б):
        if А[і] == Б[й]:
            і += 1
            й += 1
            continue
        краще = None
        for дй in range(0, min(400, len(Б) - й - ВІКНО + 1)):
            for п in індекс.get(tuple(Б[й + дй:й + дй + ВІКНО]), ()):
                if п >= і:
                    if краще is None or (п - і) + дй < краще[0]:
                        краще = ((п - і) + дй, п, й + дй)
                    break
            if краще and дй > краще[0]:
                break
        if not краще:
            вих.append((і, len(А)))
            return вих
        if краще[1] > і:
            вих.append((і, краще[1]))
        і, й = краще[1], краще[2]
    if і < len(А):
        вих.append((і, len(А)))
    return вих


def місце_коду(порядок_з, порядок_без):
    """Місце, що не взяло. Відрізки виконання, які значення додало (`блоки`): перший рядок, що пише слід у запис ходу
    (`незнайомі`/`не_взято`/…), — «пише слід»; нема — останній рядок `мовний_шар.py` останнього відрізка, де він є
    (там обробка значення скінчилась), — «без запису»."""
    бб = блоки(порядок_з, порядок_без)
    for п, к in бб:
        for x in порядок_з[п:к]:
            if _ЗАПИС_РЯДОК.search(рядок_коду(x[0], x[1])):
                return '%s:%d (%s)' % x, рядок_коду(x[0], x[1]), 'пише слід'
    for п, к in reversed(бб):
        мш = [x for x in порядок_з[п:к] if x[0].endswith('мовний_шар.py')]
        if мш:
            x = мш[-1]
            return '%s:%d (%s)' % x, рядок_коду(x[0], x[1]), 'без запису'
    if бб:
        x = порядок_з[бб[0][1] - 1]
        return '%s:%d (%s)' % x, рядок_коду(x[0], x[1]), 'без запису'
    return '—', '', 'виконання те саме'


def _є_у(в, у):
    """Те, що значення дає соло, стоїть у полі паспорта ходу (рівне, елементи списку чи дослівно в тексті)."""
    if в == у:
        return True
    if у is None:
        return False
    if isinstance(в, list) and isinstance(у, list):
        return all(x in у for x in в)
    вт = json.dumps(в, ensure_ascii=False, sort_keys=True).strip('"')
    return bool(вт) and вт in json.dumps(у, ensure_ascii=False, sort_keys=True)


def соло(обʼєкти, о, знечинене=False):
    """Лише це значення в `update` (решта `update` вилучена): чи бере його код, коли нема іншого джерела того самого поля
    (дубль, який код узяв, вилучення не міняє паспорта). `знечинене` — те саме з `знечинити` (уривок лишено)."""
    джерело = знечинити(обʼєкти, о) if знечинене else обʼєкти
    if джерело is None:
        return None
    нові = copy.deepcopy(джерело)
    for но, об in enumerate(нові):
        if not isinstance(об.get('update'), dict):
            continue
        upd = {}
        for н2, поле, і in о['місця']:
            if н2 != но:
                continue
            е = об['update'][поле] if і is None else об['update'][поле][і]
            if і is None:
                upd[поле] = е
            else:
                upd.setdefault(поле, []).append(е)
        об['update'] = upd
    return нові


def вилучити(обʼєкти, о):
    нові = copy.deepcopy(обʼєкти)
    for но, поле, і in sorted(о['місця'], key=lambda x: (x[0], -(x[2] if x[2] is not None else -1))):
        upd = нові[но].get('update')
        if і is None:
            upd.pop(поле, None)
        else:
            del upd[поле][і]
    return нові


