def слово_у(уривок, об):
    """Уривок цілими словами (межі слів з обох боків) у тексті об'єкта — будь-якої довжини: «−10», «+18»."""
    у = норма(уривок)
    return bool(у) and re.search(r'(?<!\w)' + re.escape(у) + r'(?!\w)', норма(json.dumps(об, ensure_ascii=False))) is not None


def вирівняти(уривок, її):
    """Недослівний `quote` (модель змінила відмінок: «зимова прогулянка» при «зимову прогулянку») → її відрізок з тих
    самих слів: стільки ж слів поспіль, кожне з тим самим початком (4 знаки чи все коротше слово). Будовою, без змісту."""
    сл = re.findall(r'[\w\'+−-]+', норма(уривок))
    if not сл:
        return []
    вих = []
    for р in її:
        рс = [(м.group(0), м.start(), м.end()) for м in re.finditer(r'[\w\'+−-]+', норма(р))]
        for і in range(len(рс) - len(сл) + 1):
            if all(рс[і + к][0][:min(4, len(с), len(рс[і + к][0]))] == с[:min(4, len(с), len(рс[і + к][0]))]
                   and abs(len(рс[і + к][0]) - len(с)) <= 3 for к, с in enumerate(сл)):
                вих.append(норма(р)[рс[і][1]:рс[і + len(сл) - 1][2]])
    return list(dict.fromkeys(вих))


