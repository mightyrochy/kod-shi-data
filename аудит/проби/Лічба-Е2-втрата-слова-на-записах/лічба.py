def норма(т):
    т = str(т).lower().replace('’', "'").replace('ʼ', "'").replace('`', "'").replace('ё', 'е')
    т = re.sub(r'[«»"“”„]', '', т)
    return re.sub(r'\s+', ' ', т).strip(' .,;:!?')


def кирилиця(т):
    return isinstance(т, str) and re.search(r'[а-яіїєґ]', т.lower()) is not None


def уривки(v, ключ=None):
    """[(ключ, рядок)] — усі непорожні рядки значення (рекурсивно)."""
    if isinstance(v, dict):
        return [x for к, з in v.items() for x in уривки(з, к)]
    if isinstance(v, list):
        return [x for з in v for x in уривки(з, ключ)]
    if isinstance(v, str) and v.strip():
        return [(ключ, v.strip())]
    return []


def без_уривків(v):
    if isinstance(v, dict):
        return {к: без_уривків(з) for к, з in v.items() if к not in КЛЮЧІ_УРИВКА}
    if isinstance(v, list):
        return [без_уривків(з) for з in v]
    return v


def атоми(v):
    """Коди змісту: листки без `quote`, порожніх і загальних кодів; рядки — нормовані."""
    вих = set()
    if isinstance(v, dict):
        for к, з in v.items():
            if к not in КЛЮЧІ_УРИВКА:
                вих |= атоми(з)
    elif isinstance(v, list):
        for з in v:
            вих |= атоми(з)
    elif isinstance(v, bool) or v is None:
        pass
    elif isinstance(v, (int, float)):
        вих.add(str(v))
    elif isinstance(v, str):
        н = норма(v)
        if н not in ПОРОЖНІ_КОДИ:
            вих.add(н)
    return вих


