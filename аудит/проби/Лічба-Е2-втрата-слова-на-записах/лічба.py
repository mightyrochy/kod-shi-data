def знечинити(обʼєкти, о):
    """Вилучити лише значення, лишивши її уривок: `{quote, value}` → `{quote, value: unknown}`; річ `{quote, ознаки}` →
    `{quote}`; без `quote` — як `вилучити` (значення й є уривком)."""
    нові = copy.deepcopy(обʼєкти)
    for но, поле, і in о['місця']:
        upd = нові[но].get('update')
        е = upd[поле] if і is None else upd[поле][і]
        if not (isinstance(е, dict) and isinstance(е.get('quote'), str)):
            return None
        е2 = {'quote': е['quote'], 'value': 'unknown'} if 'value' in е else {'quote': е['quote']}
        if і is None:
            upd[поле] = е2
        else:
            upd[поле][і] = е2
    return нові


