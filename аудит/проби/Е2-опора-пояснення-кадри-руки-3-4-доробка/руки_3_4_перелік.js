const fs = require("fs"), vm = require("vm");
const код = fs.readFileSync(process.argv[2] || "джерела/показ/збирання_руки.js", "utf8");
const сцена = async (рука, {дійшли = true, кадри = 2, мова = false, неОбраз = false} = {}) => {
  const виклики = []; let останні = {надіслано: 0, дійшло: 0, жодного: false}, переліків = 0;
  const r = {руки: {[рука]: "P" + рука}, руки_перепис: {[рука]: "RW \"__ПРОЗА__\""}, перелік_прози: "LIST \"__ПРОЗА__\"",
             руки_без_кадрів: {руки: {[рука]: "P" + рука + " no_frames"}, перепис: {[рука]: "RW no_frames \"__ПРОЗА__\""}}};
  const світ = {console: {log() {}, warn() {}, error() {}},
    ЗБ: {пул: r, вхід_рук: {}, почато: 0, мапаМіток: {}, ранніВідповіді: new Map(), ключ: [рука], стадії: [null], етап: [0], діагноз: []},
    КРОК_П: {складання: "assembly"}, СТАДІЯ_П: {}, МАКС_ТОКЕНІВ_П: 4000, ОБРАЗІВ_ПЕРШОЇ_П: 3, МОДЕЛЬ_МОВИ_П: !мова,
    ОСТАННІ_ЗАГОЛОВКИ_П: {}, стеляСкладанняП: () => 4000, показатиТокени() {}, поступЗміненоП() {},
    етапНеДійшов: (з, e) => ({помилка: String(e)}), етапВиклику: () => ({крок: "assembly"}),
    модельРукиП: async (промпт, фото) => {
      const н = Array.isArray(фото) ? фото.filter(Boolean).length : (фото ? 1 : 0);
      const з = світ.к.отриматиЗапитОстанній(), було = виклики.length ? виклики[виклики.length - 1].прапор : false;
      виклики.push({чого: з.чого.split(" · ")[0], кадрів: н, прапор: світ.к.описБезКадрів(), поставив: !було && світ.к.описБезКадрів()});
      останні = {надіслано: н, дійшло: дійшли ? н : 0, жодного: н > 0 && !дійшли};
      return н && !дійшли ? "blind" : "prose"; },
    дійшлоКадрівП: () => останні,
    містП: async (_, вх) => вх.перелік_речей
      ? {проза_руки: вх.текст_моделі, розбір: {перелік_моделі: true}, опис_образ: (неОбраз && !переліків++) ? false : true,
         мова: {порушення: []}}
      : {проза_руки: вх.текст_моделі, мова: {порушення: мова ? [{правило: "R-LNG-UA", суть: "x"}] : []}}};
  vm.createContext(світ);
  vm.runInContext(код + "\nthis.к = створитиКонтекстРуки(0); this.скл = стадіяСкладання; this.бк = стадіяРукБезКаталогу;", світ);
  світ.к.фотоРечейРуки = кадри ? Array.from({length: кадри}, (_, і) => ({дані: "k" + і})) : null;
  await світ.бк(світ.к, {...(await світ.скл(світ.к, {промптСкладання: r.руки[рука], складеноКодом: null, вибірРечей: null})), ітерацій: 0});
  return {прапор: світ.к.описБезКадрів(), виклики};
};
module.exports = {сцена};
