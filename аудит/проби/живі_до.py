"""Добирає ДО сцени на коді-предку лише для потрібного режиму.

Старий виклик: живі_до.py <id> [SHA]. Режим — з живі_сцени.txt;
--режим 'повне +фото' явно задає мірило. Старі код.txt з чотирма полями
читаються без міграції: режим підтверджує виконаний шлях у лог.txt.
Брак такого доказу не означає повне. Історія: git fetch --unshallow.
"""
import argparse
import pathlib
import re
import subprocess as sp

Т = pathlib.Path(__file__).resolve().parent
КОР = str(Т.parents[1])


def г(*а):
    """Читає Git без зміни робочого дерева."""
    р = sp.run(['git', '-c', 'core.quotepath=false', '-C', КОР, *а], capture_output=True, text=True)
    return р.stdout.strip() if р.returncode == 0 else None


def рядки(ім):
    """Читає чинний реєстр без коментарів."""
    return [р.split('|') for р in (Т / ім).read_text(encoding='utf-8').splitlines() if р and р[0] != '#']


def режим(опис):
    """Відділяє назву режиму реєстру від приміток і вимоги фото."""
    return опис.split('(', 1)[0].replace('+фото', '').strip(), '+фото' in опис


def сумісний(потрібний, лог):
    """Підтверджує режим виконаним шляхом, а не написом «показ ПОВНИЙ».

    Невідомі й незавершені шляхи утримуються: сам реєстр сцени не є
    доказом режиму конкретного прогону. Функціональні проби без сліду теж.
    """
    if re.search(r'^НГ-4 · ВОНА:', лог, re.M):
        факт = 'розмова'
    elif re.search(r'^2\. збирання ', лог, re.M) and re.search(r'^2б\. чотири картки ', лог, re.M):
        факт = 'повне'
    else:
        return None
    назва, фото = режим(потрібний)
    return факт == назва and (not фото or '(FOTO=1)' in лог)


def зріз():
    """Фіксує SHA всіх refs одним читанням перед оглядом артефактів."""
    return [р.split(' ', 1) for р in (г('for-each-ref', '--format=%(objectname) %(refname:short)',
            'refs/remotes/origin/claude/zhyv*') or '').splitlines()]


def добрати(сц, код, потрібний, рефи):
    """Повертає найближчий сумісний ДО й лічбу причин відмови на сталому зрізі."""
    голови = {реф: sha for sha, реф in рефи}
    рез = [(р[1], р[2], 'origin/' + р[3], р[4], р[5])
           for р in рядки('живі_прогони.txt') if р[0] == сц]
    for голова, реф in рефи:
        for ф in (г('ls-tree', '-r', '--name-only', голова) or '').splitlines():
            if ф.endswith('/код.txt'):
                п = (г('show', f'{голова}:{ф}') or '').split() + ['?'] * 4
                if п[1] == сц:
                    рез.append((п[2], п[0], реф, ф.rsplit('/', 1)[0], п[3]))
    предки, чужі, несумісні, невідомі = [], 0, 0, 0
    for ет, sha, реф, тека, мод in рез:
        голова = голови.get(реф)
        if sha == '?' or г('cat-file', '-e', sha + '^{commit}') is None or г('merge-base', '--is-ancestor', sha, код) is None:
            чужі += 1
            continue
        лог = г('show', f'{голова}:{тека}/лог.txt') if голова else ''
        збіг = сумісний(потрібний, лог or '')
        if збіг is None:
            невідомі += 1
        elif not збіг:
            несумісні += 1
        else:
            предки.append((int(г('rev-list', '--count', sha)), ет, sha, реф, тека, мод, голова))
    return max(предки) if предки else None, (чужі, несумісні, невідомі), len(предки)


def головна():
    """Зберігає позиційні виклики та явно показує межі порівняння."""
    п = argparse.ArgumentParser(description=__doc__)
    п.add_argument('сцена')
    п.add_argument('код', nargs='?', default='HEAD')
    п.add_argument('--режим', help='режим міряла з живі_сцени.txt; типово поле сцени')
    а = п.parse_args()
    с = next((р for р in рядки('живі_сцени.txt') if р[0] == а.сцена), None)
    if not с:
        п.error(f'сцени {а.сцена} нема в живі_сцени.txt')
    потрібний = а.режим if а.режим is not None else с[4]
    назви = {режим(р[4])[0] for р in рядки('живі_сцени.txt')}
    if режим(потрібний)[0] not in назви:
        п.error(f'невідомий режим {потрібний!r}; назви беруться з живі_сцени.txt')
    код = г('rev-parse', '--verify', а.код + '^{commit}')
    if not код:
        п.error(f'немає коміту {а.код}')
    рефи = зріз()
    print('СЦЕНА ' + '|'.join(с[:4]) + f'\n  режим міряла {потрібний} · руки {с[5]} · {с[6]}\n  питання: {с[7]}\n  краще: {с[8]}')
    до, (чужі, несумісні, невідомі), кількість = добрати(а.сцена, код, потрібний, рефи)
    print(f'  зріз refs {len(рефи)} · несумісний режим {несумісні} · без доказу режиму {невідомі} · поза предками чи без SHA {чужі}')
    if до is None:
        п.exit(1, f'ДО режиму {потрібний!r} на коді-предку {код} нема. Порівняння не виконано.\n')
    _, ет, sha, реф, тека, мод, голова = до
    змін = len((г('diff', '--name-only', sha, код, '--', 'джерела/') or '').splitlines())
    print(f'ДО = {ет} {реф}:{тека}\n  джерело refs {голова}\n  режим підтверджено лог.txt\n'
          f'  код {sha} · до {код} комітів {г("rev-list", "--count", sha + ".." + код)}, '
          f'файлів джерела/ змінено {змін} · моделі {мод}\n'
          f'  дата коду {г("show", "-s", "--format=%cI", sha)} · дату прогону див. лог.txt\n'
          f'  файли: {" ".join((г("ls-tree", "--name-only", голова + ":" + тека) or "").split())}\n'
          f'  інших сумісних результатів на предках {кількість - 1}; історичний ДО не доводить причину змін')


if __name__ == '__main__':
    головна()
