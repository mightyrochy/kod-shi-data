#!/bin/bash
# Вимір межі пулу без моделі (доробка #4529): сторінка гілки з `латка_виміру.py` і пулом 43 400 на мості, «міст» —
# записані відповіді прогону `аудит/проби/Живий-через-міст/` (міст_запис.py), кроки жінки — повтор_вимір.js.
# Збірка (з кореня):  git worktree add --detach /tmp/вим HEAD; скопіювати в /tmp/вим/джерела незатрекані каталоги
#   (`каталог_*.xml*`, `.таблиця_каталогу`, `*кеш_кольорів.json`); python3 <ця тека>/латка_виміру.py /tmp/вим/джерела;
#   у /tmp/вим/джерела/показ/стадії_збирання.js БЮДЖЕТ_ПУЛУ_МОСТА_П = 43400; build_артефакт.py → $STOR/index.html.
# Повтор із пулом 15 000 (знаки запиту складання ПІСЛЯ) — те саме з БЮДЖЕТ_ПУЛУ_МОСТА_П = 15000 (як на гілці), інший
#   $STOR і PORT; знаки — вимір.py на <тека виходу>/стенд/службове/*/обміни.jsonl.
# Запуск із цієї теки: bash прогін.sh <тека виходу>; потім з кореня: python3 <ця тека>/межа_пулу.py <тека виходу>
cd "$(dirname "$0")"
OUT=$(realpath -m "${1:?тека виходу}"); mkdir -p "$OUT/стенд"
export STOR=${STOR:-/tmp/стенд-вим} PYODIDE=${PYODIDE:-/tmp/pyodide} PRODUCT_MODEL=claude-sonnet-5-5 NODE_PATH=/opt/node-tools/node_modules
PORT=${PORT:-8792}
python3 міст_запис.py $PORT "$OUT/журнал_моста.jsonl" >> "$OUT/стенд/міст.лог" 2>&1 & M=$!
sleep 1
for t in ${SCENES:-с1_новорічна_вечірка с2_мінус_вісім_офіс с3_дощ_замшеві_чоботи с4_побачення_19_30 с5_весілля_сестри с6_ювілей_свекрухи с7_театр_тріада с8_мінус_десять_сніг}; do
  echo "$(date -u +%H:%M:%S) старт $t"
  node повтор_вимір.js "$t" "$OUT" $PORT > "$OUT/стенд/$t.лог" 2>&1; echo "$(date -u +%H:%M:%S) кінець $t rc=$?"
done
kill $M
