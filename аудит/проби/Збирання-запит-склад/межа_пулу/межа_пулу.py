"""Межа пулу складання без моделі (доробка #4529, вада 1 перевірки): скільки речей, які Sonnet 5.5 через справжній міст
узяла з пулу в образи складання, лишилось би в пулі при бюджеті 43 400 / 21 700 / 15 000 / 11 000 токенів.

Звідки числа. Сторінка (чинний код гілки + `латка_виміру.py`) проходить ті самі кроки жінки, що й прогін
`аудит/проби/Живий-через-міст/` (`повтор_вимір.js`), а «міст» (`міст_запис.py`) віддає записані відповіді того прогону —
моделі ніхто не кличе. На кожному складанні латка на ТОМУ САМОМУ повному пулі й сіді ріже його тим самим семплером під
кожен бюджет (`вимір_меж.jsonl`: id речей кожного зрізу). Узяті моделлю речі — номери з записаної відповіді складання;
номер старого пулу зводиться до речі через рядок пулу (усі поля рядка, крім номера) → рядок пулу 43 400 цього повтору →
id (`номери` латки). Річ, якої рядком не знайдено (пул зрізано іншим сідом чи поле рядка змінилось від правок),
лічиться окремо — «не зведено».

Запуск із кореня репозиторію: python3 аудит/проби/Збирання-запит-склад/межа_пулу/межа_пулу.py <тека повтору>"""
import gzip, json, os, re, sys, pathlib, statistics as st, collections
sys.path.insert(0, "джерела")
from slots import СЛОТ_ТИПУ

ТЕКА = pathlib.Path(sys.argv[1])
ЗАПИСИ = pathlib.Path("аудит/проби/Живий-через-міст/стенд/службове")
БЮДЖЕТИ = ("43400", "21700", "15000", "11000")
НОМЕР = re.compile(r"#\s*\d+\s*·\s*\d{2}")


def відкрити(ш):
    """Файл повтору: як є чи стиснений (`.gz`) — у репозиторії записи лежать стисненими."""
    ш = pathlib.Path(ш)
    return open(ш, encoding="utf-8") if ш.exists() else gzip.open(str(ш) + ".gz", "rt", encoding="utf-8")


def текст(тіло):
    return "".join(б.get("text", "") for м in тіло.get("messages") or [] for б in (м.get("content") if isinstance(м.get("content"), list) else []) if б.get("type") == "text")


ПОЛЯ_КЛЮЧА = ("type", "color", "hex", "price", "L", "cut")


def ключ(кол, р):
    """Рядок пулу без номера → ключ із полів, що називають саму річ: решту полів дроту (`length`, `formality`,
    `fabric_bands` …) правки після запису моста шлють інакше чи вперше, і той самий рядок не збігався (вимір на с1–с5)."""
    return json.dumps({к: в for к, в in zip(кол, р) if в is not None and к in ПОЛЯ_КЛЮЧА}, ensure_ascii=False,
                      sort_keys=True)


def рядки_пулу(т):
    п = json.loads(т)["pool"]
    кол = п["cols"]
    return {р[0]: ключ(кол[1:], р[1:]) for р in п["rows"]}, len(т), len(json.dumps(п["rows"], ensure_ascii=False))


def взяті(відповідь):
    в = json.loads(відповідь)
    т = "".join(б.get("text", "") for б in в.get("content") or [] if б.get("type") == "text")
    try:
        обр = json.loads(т).get("outfits") or []
    except ValueError:
        return set()
    return {re.sub(r"\s", "", НОМЕР.search(x).group(0)) for о in обр for x in (о.get("items") or [])
            if isinstance(x, str) and НОМЕР.search(x)}


журнал = [json.loads(р) for р in відкрити(ТЕКА / "журнал_моста.jsonl")]
записані = {}
for с in {з["сит"] for з in журнал}:
    записані[с] = collections.defaultdict(list)
    for р in open(ЗАПИСИ / с / "обміни.jsonl", encoding="utf-8"):
        д = json.loads(р)
        if д.get("відповідь"):
            записані[с][str(д.get("прохід"))].append(д)
виміри = collections.defaultdict(list)          # (ситуація, прохід) → рядки латки по черзі
for ф in sorted(set(ТЕКА.glob("стенд/службове/*/вимір_меж.jsonl")) | {ш.with_suffix("") for ш in ТЕКА.glob("стенд/службове/*/вимір_меж.jsonl.gz")}):
    for р in відкрити(ф):
        д = json.loads(р)
        м = json.loads(д["рядок"])
        if "рядки" in м:
            р_ = collections.defaultdict(list)
            for к, ід_ in м["рядки"].items():
                р_[ключ(*zip(*json.loads(к).items()))] += ід_
            м["рядки"] = dict(р_)
        виміри[(ф.parent.name, str(д["прохід"]))].append(м)

Л = collections.Counter()
у_зрізі = {б: [0, 0] for б in БЮДЖЕТИ}         # узяті моделлю речі: у зрізі / зведено
умовно = {б: [0, 0] for б in БЮДЖЕТИ}          # ті з них, що в зрізі 43 400 цього сіду: у зрізі б / усього
вкладено = {б: [0, 0] for б in БЮДЖЕТИ}        # усі речі зрізу 43 400: у зрізі б / усього
брак = {б: [0, 0, 0, 0] for б in БЮДЖЕТИ}    # слотів, де зріз має менше різних речей, ніж модель узяла: брак / речей узято / слотів з браком / слотів
nn = {б: [] for б in БЮДЖЕТИ}; ток = {б: [] for б in БЮДЖЕТИ}; повні = []; знаки = []
бачені = set()
for з in журнал:
    # кожен записаний обмін — раз: зайве складання повтору (заміна речі, повтор після збою) бере вже взятий запис
    if "запит" not in з or з.get("запис") is None or (з["сит"], з["прохід"], з["запис"]) in бачені:
        Л["складань повтору поза записами"] += "запит" in з
        continue
    бачені.add((з["сит"], з["прохід"], з["запис"]))
    _, зн_запиту, _ = рядки_пулу(з["запит"])
    # рядок латки цього складання: той, чий зріз 43 400 — рівно речі пулу запиту (рядки запиту → id через рядки
    # повного пулу латки); пакет із кеша сторінки латку вдруге не кличе, тож один рядок латки може стояти за кількома
    пул_з = json.loads(з["запит"])["pool"]
    ключі_з = [ключ(пул_з["cols"][1:], р[1:]) for р in пул_з["rows"]]
    def збіг(м):
        ід43 = set(м["межі"]["43400"]["ід"])
        return len({і for к in ключі_з for і in м["рядки"].get(к, [])} & ід43) / max(len(ід43), 1)
    оцінки = sorted(((збіг(м), н) for н, м in enumerate(виміри[(з["сит"], з["прохід"])]) if "рядки" in м), reverse=True)
    м = виміри[(з["сит"], з["прохід"])][оцінки[0][1]] if оцінки and оцінки[0][0] >= 0.9 else None
    if os.environ.get("NALAHODA"): print(з["сит"][:3], з["прохід"], з["запис"], len(ключі_з), [(round(о, 2), н) for о, н in оцінки])
    Л["збіг пулу запиту з рядком латки, %"] = min(Л.get("збіг пулу запиту з рядком латки, %", 100), int(100 * оцінки[0][0]) if оцінки else 0)
    if м is None:
        Л["складань без рядка латки"] += 1
        continue
    д = записані[з["сит"]][з["прохід"]][з["запис"]]
    старі, _, _ = рядки_пулу(текст(json.loads(д["запит"])))
    узято = взяті(д["відповідь"]) & set(старі)
    зріз = {б: set(м["межі"][б]["ід"]) for б in БЮДЖЕТИ if б in м["межі"]}
    утр = set(м.get("утримані") or [])
    Л["складань"] += 1; Л["узято моделлю"] += len(узято)
    повні.append(м["повний"]["ток"]); знаки.append(зн_запиту)
    for б in зріз:
        nn[б].append(м["межі"][б]["n"]); ток[б].append(м["межі"][б]["ток"])
        вкладено[б][0] += len(зріз[б] & зріз["43400"]); вкладено[б][1] += len(зріз["43400"])
    # (2) різноманіття: скільки різних речей кожного слота модель узяла в десять образів — і скільки їх дає зріз
    тип = lambda к: СЛОТ_ТИПУ.get(json.loads(к).get("type"), json.loads(к).get("type"))
    слот_ід = {і: тип(к) for к, ід_ in м["рядки"].items() for і in ід_}
    k = collections.Counter(тип(старі[н]) for н in узято)
    for б in зріз:
        p = collections.Counter(слот_ід.get(і) for і in зріз[б])
        for с, kс in k.items():
            брак[б][1] += kс; брак[б][3] += 1
            if p[с] < kс:
                брак[б][0] += kс - p[с]; брак[б][2] += 1
    for н in узято:
        ід = set(м["рядки"].get(старі[н]) or [])
        if not ід:
            Л["не зведено"] += 1
            continue
        Л["зведено"] += 1; Л["з них з прапорцем утримання"] += bool(ід & утр)
        for б in зріз:
            у_зрізі[б][1] += 1; у_зрізі[б][0] += bool(ід & зріз[б])
            if ід & зріз["43400"]:
                умовно[б][1] += 1; умовно[б][0] += bool(ід & зріз[б])

пр = lambda x: f"{x[0]} з {x[1]} ({100 * x[0] / max(x[1], 1):.0f} %)"
print(f"складань: {Л['складань']} (без рядка латки — {Л['складань без рядка латки']}, зайвих у повторі —"
      f" {Л['складань повтору поза записами']}); речей, узятих моделлю в записах моста: {Л['узято моделлю']}; зведено до"
      f" речі повного пулу цього повтору: {Л['зведено']} (не зведено {Л['не зведено']}); з прапорцем утримання —"
      f" {Л['з них з прапорцем утримання']}")
print(f"повний пул: {st.mean(повні):,.0f} токенів (від {min(повні):,} до {max(повні):,}); запит складання з пулом 43 400:"
      f" {st.mean(знаки):,.0f} знаків")
print()
print("| бюджет пулу, ток | позицій | токенів пулу | речі зрізу 43 400, що лишаються | узяті моделлю, що лишаються (серед тих, що в зрізі 43 400 цього сіду) | узяті моделлю в зрізі (з усіх зведених) | брак різних речей слота проти взятого моделлю (слотів з браком) |")
print("|---|---|---|---|---|---|---|")
for б in БЮДЖЕТИ:
    print(f"| {int(б):,} | {st.mean(nn[б]):.0f} | {st.mean(ток[б]):,.0f} | {пр(вкладено[б])} | {пр(умовно[б])} | {пр(у_зрізі[б])} | {пр(брак[б][:2])} ({брак[б][2]} з {брак[б][3]}) |")
