# -*- coding: utf-8 -*-
"""Траса меж пулу несе рівень речі, і він той самий, що дає вибірка; старі записи без рівнів читаються «не записано»."""
import ast, textwrap, pathlib, gzip, importlib.util, json, sys, tempfile
from pathlib import Path

ТУТ = Path(__file__).resolve().parent
КОРІНЬ = ТУТ.parents[3]
sys.path.insert(0, str(КОРІНЬ / "джерела"))
import семплер as С
from добір_вагою import рівні

# 1. Слот із двома гілками й трьома рівнями: рівень речі = той, під яким її бере сама вибірка.
ядро = [{"id": "а", С.ПОЛЕ_РАНГУ: (0, 0)}, {"id": "б", С.ПОЛЕ_РАНГУ: (1, 0)}, {"id": "в", С.ПОЛЕ_РАНГУ: (2, 2)},
        {"id": "г", С.ПОЛЕ_РАНГУ: (0, 0)}]
межа = [{"id": "д", "гілка": "на межі", С.ПОЛЕ_РАНГУ: (3, 1)}, {"id": "е", "гілка": "на межі", С.ПОЛЕ_РАНГУ: (3, 0)}]
слот = ядро + межа
очікувано = {"а": 0, "б": 1, "в": 2, "г": 0, "д": 1, "е": 0}
за_вибіркою = {}
for гілка in ({"ядро": ядро, "на межі": межа}).values():
    for л, рч in С._рівні_речей(гілка).items():
        за_вибіркою.update({р["id"]: л for р in рч})
# сам блок латки (її `РІВНІ`, вирізаний з тексту) на цьому слоті: пул з одним слотом
_текст = (ТУТ / "латка_виміру.py").read_text(encoding="utf-8")
_блок = _текст.split("РІВНІ = '''", 1)[1].split("'''", 1)[0]
_мв = {}
exec("if True:\n" + _блок, {"пак": {"кандидати": {"верх": слот}}, "_мв": _мв, "_С": С})
отримано = _мв["рівні"]
пор = [tuple(r[С.ПОЛЕ_РАНГУ]) for r in ядро]
ок = отримано == очікувано == за_вибіркою and рівні(пор) == [0, 1, 2, 0]
# вибірка від виклику не міняється
ок &= [r["id"] for r in С.вибрати_зі_слота(слот, 3, 7)] == [r["id"] for r in С.вибрати_зі_слота(слот, 3, 7)]

# 2. Читач: старий запис без «рівні» → None; новий → число.
спец = importlib.util.spec_from_file_location("вимір", КОРІНЬ / "аудит" / "звіти" / "крамниці-рівна-черга" / "вимір.py")
В = importlib.util.module_from_spec(спец); спец.loader.exec_module(В)
ок &= В.рівень_речі(None, "а") is None and В.рівень_речі({}, "а") is None
ок &= В.рівень_речі(отримано, "в") == 2 and В.рівень_речі(отримано, "нема") is None

# 3. Латка вписує блок, що кличе рівні_слота (парситься, якір один).
з = tempfile.mkdtemp()
ф = Path(з) / "міст_пакет.py"
ф.write_text("def f():\n    if not пак.get(\"готово\") or _вага(пак) <= _б_зрізу:\n        pass\n", encoding="utf-8")
sys.argv = ["л", з]
exec(compile((ТУТ / "латка_виміру.py").read_text(encoding="utf-8"), "латка", "exec"))
т = ф.read_text(encoding="utf-8"); ast.parse(т)
ок &= '_мв["рівні"]' in т and "_С._рівні_речей" in т
# Читаємо той самий блок, що піде у сторінку, зі зрізом із двох позицій.
початок = т.index('        _мв["рівні"] = {}')
кінець = т.index('        _мв["утримані"]', початок)
повний = {"кандидати": {"взуття": слот}}
зріз = {"кандидати": {"взуття": [межа[0], ядро[0]]}}
вхід = {"пак": повний, "_паки_в": {15000: зріз}, "_С": С, "_мв": {}}
exec(textwrap.dedent(т[початок:кінець]), вхід)
позиції = вхід["_мв"]["траса"]
очікувані_позиції = [("повний", п, за_вибіркою[р["id"]]) for п, р in enumerate(слот, 1)]
очікувані_позиції.extend([(15000, 1, 1), (15000, 2, 0)])
ок &= [(р["межа"], р["позиція"], р["рівень"]) for р in позиції] == очікувані_позиції
print("рівні траси:", отримано, "OK" if ок else "ПОМИЛКА")
sys.exit(int(not ок))
