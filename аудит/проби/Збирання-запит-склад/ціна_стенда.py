"""Ціна, вихід і секунди складання, ремонту й вибору на стенді за підпискою (журнал `міст_claude.py`), ДО → ПІСЛЯ.
Виклик журналу зіставляється з обміном сторінки за проходом і довжиною промпта (±1 %). Долари — `total_cost_usd`
`claude -p` (ціна API за тим самим обліком; кеш тут — кеш Claude Code, а не моста). Запуск із кореня репозиторію."""
import json, sys, collections, statistics as st
sys.path.insert(0, "аудит/проби/Збирання-запит-склад")
sys.argv = sys.argv[:1]
import вимір as В
НАБОРИ = {"ДО (живий-як-людина-4, 24aa7805)": "аудит/проби/живий-як-людина-4/стенд",
          "ПІСЛЯ (цей PR)": "аудит/проби/Збирання-запит-склад/живий/стенд"}
for назва, тека in НАБОРИ.items():
    журнал = [json.loads(l) for l in open(тека + "/журнал_моделі_продукту.jsonl")]
    р = collections.defaultdict(list)
    for сит in ("с8_мінус_десять_сніг", "с5_весілля_сестри"):
        ф = f"{тека}/службове/{сит}/обміни.jsonl"
        try:
            рядки = list(В.рядки(ф))
        except FileNotFoundError:
            рядки = list(В.рядки(ф + ".gz"))
        for д in рядки:
            if д.get("статус") != 200:
                continue
            текст, т = В.тіло(д)
            к = В.вид(т)
            if not к:
                continue
            пр = f"{сит} · {д.get('прохід')}"
            зб = [ж for ж in журнал if ж.get("прохід") == пр and abs(ж["промпт_симв"] - len(текст)) <= 0.01 * len(текст)]
            if зб:
                ж = min(зб, key=lambda ж: abs(ж["промпт_симв"] - len(текст)))
                р[к].append((ж["usd"], ж.get("вихід") or 0, ж["с"]))
    print(f"\n{назва}")
    for к in ("складання", "ремонт", "вибір"):
        x = р[к]
        if x:
            print(f"  {к}: викликів {len(x)}; $ середнє {st.mean(a for a, _, _ in x):.3f}, усього {sum(a for a, _, _ in x):.2f};"
                  f" токенів виходу середнє {st.mean(b for _, b, _ in x):,.0f}; секунд середнє {st.mean(c for _, _, c in x):.1f}"
                  f" (макс {max(c for _, _, c in x):.0f})")
