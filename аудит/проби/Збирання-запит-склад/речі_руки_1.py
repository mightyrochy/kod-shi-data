"""Речі образу руки 1 на картці (стенд пише `руки.jsonl` зі сторінки): ДО (живий-як-людина-4) і ПІСЛЯ (цей PR).
Запуск із `аудит/проби`: python3 Збирання-запит-склад/речі_руки_1.py"""
import json, gzip
def рядки(ф):
    try:
        return [json.loads(l) for l in open(ф)]
    except FileNotFoundError:
        return [json.loads(l) for l in gzip.open(ф + ".gz", "rt")]
for назва, т in (("ДО", "живий-як-людина-4/стенд/службове"), ("ПІСЛЯ", "Збирання-запит-склад/живий/стенд/службове")):
    for сит in ("с8_мінус_десять_сніг", "с5_весілля_сестри"):
        р = рядки(f"{т}/{сит}/руки.jsonl")
        for прохід in sorted({x["прохід"] for x in р}):
            x = [x for x in р if x["прохід"] == прохід and x.get("позиції")][-1]
            for п in x["позиції"]:
                if п.get("рука") == "1":
                    print(f"{назва} · {сит[:2]} · {прохід}: " + " | ".join(к.get("назва") or "?" for к in п.get("речі") or []))
