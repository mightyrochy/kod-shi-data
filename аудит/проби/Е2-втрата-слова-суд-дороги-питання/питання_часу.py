"""МІРИЛО ДОРОБКИ «суд дороги» (дошка 16281, 16257): чи питання про час на ногах доходить до жінки.

Коли вона не назвала ні тривалості події, ні дороги пішки, ціна каблука (K-END-01, `аксесуари_носіння.вартість_носіння`)
дає «питання» з заявою `wear_cost_no_duration` (поверхню названо) чи `wear_cost_no_duration_surface` (не названо й її).
Тут — ті самі сцени двома шляхами продукту:
- рука 1–2: питання → повідомлення картки (`міст_відповіді._питання_кодами`, `_для_всіх`, `_пункти_картки`) —
  чи пункт картки несе заяву жінці (не `для_всіх`, адресат не журнал);
- «Оціни мій образ»: `оцінка_образу.суд` над її речами з фото (жакет, спідниця, туфлі) → картка «Чого я не знаю»
  (`прийняти_оцінку`, `не_знаю[].входи`) і вхід моделі (`невідоме_для_моделі`, `unknown[].statements`) — чи є там код
  заяви часу; заодно — причина пункту чекліста A9 (K-END-02, «тривалість нагоди») і чи його вхід лічить дорогу пішки.
Контроль — сцени з часом (20 хв пішки; 8 год): питання нема, і його не має бути.

Запуск з кореня репозиторію: `python3 -W ignore аудит/проби/Е2-втрата-слова-суд-дороги-питання/питання_часу.py`.
Останній рядок — `сцен без часу: N · питання жінці на картці руки: A · на картці оцінки: B · у вході моделі оцінки: C`."""
import json, os, sys
КОРІНЬ = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
sys.path.insert(0, os.path.join(КОРІНЬ, 'джерела'))
os.chdir(os.path.join(КОРІНЬ, 'джерела'))
import аксесуари_носіння as АН, міст_відповіді as М, оцінка_образу as О, colorspace as cs

КОДИ = {"wear_cost_no_duration", "wear_cost_no_duration_surface"}
СЦЕНИ = [("нічого не назвала", {}), ("бруківка без часу", {"поверхня": "бруківка"}),
         ("сніг з погоди без часу", {"опади": "сніг"}),
         ("контроль: 20 хв пішки", {"дорога_пішки_хв": 20}), ("контроль: 8 год", {"тривалість_год": 8})]
ПАРА = [dict(id="туфлі-1", слот="взуття", назва="туфлі на шпильці"), dict(id="сумка-1", слот="сумка", назва="сумка")]
вх = json.load(open('стенд_вх.json'))
ФОТО = [('ф1', 'жакет', 'верхній_шар', '#7d7f63', 'хакі'), ('ф3', 'міні-спідниця', 'низ', '#6b1f2a', 'бордовий'),
        ('ф5', 'туфлі на шпильці', 'взуття', '#e6dfd2', 'вершковий')]
речі_фото = [dict(ід=і, фото=і, назва=н, слот=с, колір=к, ошатність=6, в_образі=True,
                  вимір=dict(lab=list(cs.hx(h)), hex=h, слово=к)) for і, н, с, h, к in ФОТО]


def коди(о):
    """Коди заяв часу, що стоять у записі (рядком коду чи полем `code` заяви)."""
    return {м for м in КОДИ if '"%s"' % м in json.dumps(о, ensure_ascii=False, default=str)}


без_часу = рука = оцінка = модель = 0
for назва, сц in СЦЕНИ:
    зн = АН.вартість_носіння(ПАРА, тривалість_год=сц.get("тривалість_год"), поверхня=сц.get("поверхня"),
                             дорога_пішки_хв=сц.get("дорога_пішки_хв"), опади=сц.get("опади"))
    питання = [z for z in зн if z.get("правило") == "K-END-01" and z.get("сила") == "питання"]
    пункти = []
    for z in питання:
        пов = М._з_кодами(М._питання_кодами(z), {}.get)
        пункти += М._пункти_картки([dict(правило=z["правило"], суть=z.get("суть"), речі=z.get("речі"),
                                         повідомлення=пов, **({"для_всіх": 1} if М._для_всіх(пов) else {}))])
    їй = [з.get("code") for п in пункти if not п.get("для_всіх") for з in (п.get("повідомлення") or {}).get("statements") or []
          if з.get("recipient") not in ("journal", "stylist") and з.get("code") in КОДИ]
    с = О.суд(dict(вх, речі=речі_фото, сценарій_оцінки=dict(сц), крамниця=False))
    не_знаю = О.прийняти_оцінку(json.dumps({"answer": "Ок.", "verdict": "wear_as_is"}), с)["картка"]["не_знаю"]
    на_картці = sorted({в for х in не_знаю for в in х.get("входи") or [] if в in КОДИ})
    у_моделі = sorted(коди(О.невідоме_для_моделі(с)))
    a9 = [(б.get("why"), б.get("constant")) for б in с.get("без_входу") or [] if б.get("point") == "refusal_reason_physical"]
    print("%s · рука: питань K-END-01 %d, заяв часу жінці на картці %s · оцінка: на картці %s, у вході моделі %s · "
          "A9: %s" % (назва, len(питання), їй or "—", на_картці or "—", у_моделі or "—",
                      a9[0] if a9 else "вхід є"))
    print("    «Чого я не знаю» оцінки: %s" % "; ".join("+".join(х.get("входи") or [х.get("текст", "")]) for х in не_знаю))
    if питання:
        без_часу += 1
        рука += bool(їй)
        оцінка += bool(на_картці)
        модель += bool(у_моделі)
print("сцен без часу: %d · питання жінці на картці руки: %d · на картці оцінки: %d · у вході моделі оцінки: %d"
      % (без_часу, рука, оцінка, модель))
