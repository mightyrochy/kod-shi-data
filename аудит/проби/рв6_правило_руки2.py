"""Стенд: RUKA2_PRAVYLO=<ід правила> задає правило руки 2 для прогону (лише тест; продукт без змінної не чіпано).
Підміняє `правило_руки2.жереб`: перелік звужено до названого правила, коли воно має вхід; без входу чи без змінної —
жереб як був. `рв6_стенд.js` кладе цей файл у Pyodide й кличе `встановити(ід)`; проба — `python3 аудит/проби/рв6_правило_руки2.py`."""
import правило_руки2 as ПР

_СПРАВЖНІЙ = ПР.жереб


def встановити(ід):
    ПР.жереб = _СПРАВЖНІЙ
    if not ід:
        return
    запис = next((з for з in ПР.ПЕРЕЛІК if з["ід"] == ід), None)
    if запис is None:
        raise ValueError(f"RUKA2_PRAVYLO: правила {ід} нема в переліку")

    def жереб(d, п=None, перелік=ПР.ПЕРЕЛІК, діє=None, пар=None):
        if перелік is ПР.ПЕРЕЛІК and ПР.вхід(запис, d, п)[0]:
            перелік = (запис,)
        return _СПРАВЖНІЙ(d, п, перелік=перелік, діє=діє, пар=пар)
    ПР.жереб = жереб
