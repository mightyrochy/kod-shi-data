# -*- coding: utf-8 -*-
"""МІРА НАРЯДУ `Е2-втрата-слова-нерозібране-стилістці`: та сама лічба на тих самих записах і два числа понад неї.

Запускає `аудит/проби/Лічба-Е2-втрата-слова-на-записах/лічба.py` без змін — `зібрати` → `лічити` → `підсумок`, як її
`main`, — на дереві, з якого запущено (`--дерево`: корінь іншого клону, напр. `main` у `git worktree`), і пише
`підсумок.txt`, `дані.json` у `--вихід` (тека лічби ДО не перезаписується). Понад лічбу — з того самого входу
стилістки «нині» (`дріт_моделі.випадок(пакет_моделі.випадок_для_пакета(паспорт кінця запису))`), який лічба міряє:
  · ДВІЧІ — рядок `her_other_words`, який цілими словами вже стоїть в іншому ключі входу чи в іншому рядку
    `her_other_words` (слово дійшло, і його дублює решта); окремо — ПЕРЕТИН: дослівний уривок не взятого значення, що
    стоїть і в рядку `her_other_words`, і в іншому ключі, бо рядок решти — довший уривок іншого значення;
  · ЗМІСТ КОДОМ ПОЛЯ — рішення менеджера 17.11 (16309): не взяте значення, якого стилістка не бачить уривком, але чий
    зміст несе заповнене поле входу (година — `part_of_day`, смуга — `weather_band`, `month` — `season`/`date`), —
    окремим рядком із назвою поля; «→ 0» і місця лічать без них;
  · МІСЦЯ ПОВЗ — місця коду (стовпець «місце коду» лічби), де хоч одне не взяте значення стилістка нині не бачить;
  · РЕШТА ПОЗА РЯДКАМИ — рядки `her_other_words`, яких не дає уривок жодного не взятого значення запису (модель сама
    написала `rest` чи шлях дав уривок узятого значення); порівнювати ДО → ПІСЛЯ.
`--межі-слів` — застереження перевірки 16298: «стилістка бачила» бере уривок від 4 знаків підрядком (`текст_у`), з
ключем — цілими словами (`слово_у`), як решта лічби; лічба сама не змінюється.
Запуск з кореня репозиторію: `python3 аудит/проби/Е2-втрата-слова-нерозібране/міра.py --вихід <тека>
[--дерево <корінь клону>] [--межі-слів]` (~10 хв, без моделей і мережі)."""
import argparse
import collections
import importlib.util
import json
import os
import sys

а = argparse.ArgumentParser()
а.add_argument('--вихід', required=True)
а.add_argument('--дерево', default=os.getcwd())
а.add_argument('--фільтр')
а.add_argument('--межі-слів', action='store_true',
               help='застереження перевірки 16298: «стилістка бачила» — уривок цілими словами (`слово_у`), не підрядком')
арг = а.parse_args()
вихід = os.path.abspath(арг.вихід)
os.makedirs(вихід, exist_ok=True)
дерево = os.path.abspath(арг.дерево)
шлях = os.path.join(дерево, 'аудит', 'проби', 'Лічба-Е2-втрата-слова-на-записах', 'лічба.py')
spec = importlib.util.spec_from_file_location('лічба', шлях)
Л = importlib.util.module_from_spec(spec)
spec.loader.exec_module(Л)
if арг.межі_слів:
    Л.текст_у = Л.слово_у

випадки = []


class Продукт(Л.Продукт):
    def випадок(self, паспорт):
        в = super().випадок(паспорт)
        випадки.append(в)
        return в


записи, копії, без_відповіді = Л.зібрати()
if арг.фільтр:
    записи = [з for з in записи if арг.фільтр in з['запис']]
П = Продукт()
рядки, без_знахідок, за_джерелом, збої = Л.лічити(П, записи)
os.chdir(П.cwd)
# випадок лічба кличе раз на запис зі знахідками, після його рядків — порядок записів у рядках той самий
порядок = list(dict.fromkeys(р['запис'] for р in рядки))
assert len(порядок) == len(випадки), (len(порядок), len(випадки))
вхід = dict(zip(порядок, випадки))
рядки.sort(key=lambda р: (р['джерело'], р['де'], р['поле']))
п = Л.підсумок(рядки, без_знахідок, за_джерелом, копії, без_відповіді, збої, записи)


def дослівні(р):
    return [у for у in р['уривки'] + р['вирівняні'] if 'уривок не дослівний' not in р['сумнівно'] or у in р['вирівняні']]


двічі, перетин, місця_до, решта_поза = [], [], collections.Counter(), []
for з, в in вхід.items():
    case = (в or {}).get('case') or {}
    інше = {к: x for к, x in case.items() if к != 'her_other_words'}
    решта = [str(x) for x in case.get('her_other_words') or []]
    for і, x in enumerate(решта):
        де = [к for к, y in інше.items() if Л.слово_у(x, {к: y})] + [
            'her_other_words[%d]' % й for й, y in enumerate(решта) if й != і and Л.слово_у(x, y)]
        if де:
            двічі.append('%s · «%s» · ще в: %s' % (з, x, ', '.join(де)))
    свої = [р for р in рядки if р['запис'] == з and not р['сумнівно']]
    for р in свої:
        for у in дослівні(р):
            if len(Л.норма(у)) < 4:
                continue
            у_решті = sum(Л.слово_у(у, x) for x in решта)
            if у_решті and (у_решті > 1 or Л.слово_у(у, інше)):
                перетин.append('%s · %s · «%s» · her_other_words %d, ще в: %s' % (
                    р['де'], р['поле'], у, у_решті, ', '.join(к for к, x in інше.items() if Л.слово_у(у, {к: x})) or '—'))
                break
    уривки_запису = [у for р in рядки if р['запис'] == з for у in дослівні(р)]
    for x in решта:
        if not any(Л.слово_у(у, x) or Л.слово_у(x, у) for у in уривки_запису):
            решта_поза.append('%s · %s' % (з, x))
# РІШЕННЯ МЕНЕДЖЕРА 17.11 (16309): значення, зміст якого стилістка дістає кодом поля, заповненого з тих самих її слів
# у тій самій сцені, — не втрата: година — частиною дня, смуга погоди — кодом смуги; `month` — лише коли пора року чи
# дата сцени дійшла своїм полем. Поле заповнене — непорожнє, не `unknown` і не типове (`sources.<поле>.kind` ≠ default).
ПОЛЕ_ЗМІСТУ = {'hour': ('part_of_day',), 'minute': ('part_of_day',), 'part_of_day': ('part_of_day',),
               'weather_band': ('weather_band',), 'month': ('season', 'date')}


def поле_несе(р):
    case = (вхід.get(р['запис']) or {}).get('case') or {}
    for к in ПОЛЕ_ЗМІСТУ.get(р['поле'], ()):
        з = case.get(к)
        if з not in (None, '', [], {}, 'unknown') and ((case.get('sources') or {}).get(к) or {}).get('kind') != 'default':
            return к
    return None


кодом_поля, втрати = collections.Counter(), []
for р in рядки:
    if not р['сумнівно'] and р['стилістка_нині'] != 'так':
        к = поле_несе(р)
        р['зміст_кодом_поля'] = к or ''
        if к:
            кодом_поля[к] += 1
            continue
        втрати.append(р)
        місця_до[р['місце']] += 1
дод = ['', 'ПОНАД ЛІЧБУ (вхід стилістки нині, не взяті дослівні):',
       '  рядків her_other_words, що вже стоять в іншому ключі входу чи рядку решти (двічі): %d' % len(двічі)] + [
       '    ' + x for x in двічі[:30]] + [
       '  уривків не взятих значень і в решті, і поза нею (перетин довшого уривку): %d' % len(перетин)] + [
       '    ' + x for x in перетин[:30]] + [
       '  стилістка нині не бачить уривка, але зміст дістає кодом поля, заповненого з тих самих слів (рішення 17.11, '
       '16309; не втрата): %d [%s]' % (sum(кодом_поля.values()), ' · '.join('%s %d' % кв for кв in кодом_поля.most_common()) or '—'),
       '  стилістка нині не бачить — без них (мірило «→ 0»): %d' % len(втрати)] + [
       '    %s · хід %s · %s · %s · %s' % (р['запис'], р['хід'], р['поле'], р['уривки'], р['місце']) for р in втрати] + [
       '  місць коду, де не взяте значення стилістка нині не бачить (без них): %d (значень %d)' % (len(місця_до), sum(місця_до.values()))] + [
       '    %s: %d' % кв for кв in місця_до.most_common()] + [
       '  рядків her_other_words поза уривками не взятих значень запису: %d' % len(решта_поза)]
п = п + '\n' + '\n'.join(дод)
with open(os.path.join(вихід, 'підсумок.txt'), 'w', encoding='utf-8') as ф:
    ф.write(п + '\n')
with open(os.path.join(вихід, 'решта_поза_рядками.txt'), 'w', encoding='utf-8') as ф:
    ф.write('\n'.join(решта_поза) + '\n')
with open(os.path.join(вихід, 'дані.json'), 'w', encoding='utf-8') as ф:
    json.dump({'рядки': рядки, 'без_знахідок': без_знахідок, 'двічі': двічі, 'перетин': перетин}, ф, ensure_ascii=False, indent=1)
print(п)
