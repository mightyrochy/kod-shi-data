/* Записаний живий 2610-1 → справжній запасний шлях чату й завершення стенда.
   node аудит/проби/доробка_1873.js [--до] [тека доказів] */
const fs = require('fs'), path = require('path'), vm = require('vm');
const {execFileSync} = require('child_process');
const корінь = path.resolve(__dirname, '../..');
const до = process.argv.includes('--до');
const куди = process.argv.slice(2).find(а => а !== '--до');
const читати = ім => до ? execFileSync('git', ['show', '68e5ef3e7:' + ім], {cwd: корінь, encoding: 'utf8'})
  : fs.readFileSync(path.join(корінь, ім), 'utf8');
const входи = require('../огляд_коду/доробка_1873/входи.json');
const {Доказ} = require('../../джерела/прилади/доказ_прогону.js');
const питання = fs.readFileSync(path.join(корінь, 'джерела/показ.html'), 'utf8')
  .match(/aria-label="([^"]+)" id="чат-поле"/)[1];
function міст(вхід){
  return JSON.parse(execFileSync('python', ['-c',
    'import sys, мовний_шар; print(мовний_шар.мова(sys.stdin.read()))'],
    {cwd: path.join(корінь, 'джерела'), input: JSON.stringify(вхід), encoding: 'utf8',
     env: {...process.env, PYTHONUTF8: '1'}}));
}
function контекстЧату(сцена, відповідь = ''){
  const контекст = vm.createContext({console, ДОВІДНИК: входи.довідник,
    ЧАТ_П: [{хто: 'людина', текст: сцена.слова}], РЕЖИМ: 'сценарій', МОДЕЛЬ_МОВИ_П: 'offline',
    $: () => ({getAttribute: () => питання}), почиститиВетоП: п => п,
    застосуватиПаспортДоЕкрана: () => {}, малюватиМежіП: () => {},
    містП: async (_, вхід) => міст(вхід), модельМовиП: async () => відповідь,
    латинкаЧатуП: async т => т,
    повідомленнямП: async () => ({тексти: {}, записи: []}), мовоюП: async тексти => ({тексти, записи: []})});
  const шар = fs.readFileSync(path.join(корінь, 'джерела/показ/мовний_шар.js'), 'utf8');
  vm.runInContext(шар.slice(шар.indexOf('async function реплікоюП('),
    шар.indexOf('/* ── ХІД РОЗМОВИ')), контекст);
  vm.runInContext(читати('джерела/показ/паспорт.js'), контекст);
  контекст.оновитиДовідникП = async () => {};
  контекст.паспортПоРозмовіП = async () => ({паспорт: structuredClone(сцена.паспорт)});
  return контекст;
}

async function main(){
  const результат = {версія: до ? 'ДО' : 'ПІСЛЯ', чат: [], стенд: []};
  for (const сцена of входи.чат){
    const контекст = контекстЧату(сцена);
    await контекст.розмоваЯкMainП(сцена.слова, [], false, 'сценарій', [{причина: 'only_questions'}], () => true);
    const репліка = контекст.ЧАТ_П.at(-1), текст = репліка.текст;
    const вигадка = сцена.вигадки.some(ф => текст.includes(ф));
    const кодоваФраза = текст.startsWith('Записала');
    результат.чат.push({сцена: сцена.сцена, текст, вигадка, кодоваФраза, записи: репліка.мова_шару});
    if (!до && (вигадка || кодоваФраза || текст !== питання)) throw new Error('Неправильний запасний текст: ' + сцена.сцена);
  }
  for (const сцена of входи.стенд){
    const доказ = new Доказ({прилад: 'replay_1873'}), рядки = [];
    let код;
    const контекст = vm.createContext({ДОКАЗ: доказ, ЖУРНАЛ_МОДЕЛІ: сцена.виклики,
      console: {log: т => рядки.push(т)}, process: {exit: к => { код = к; }}});
    const кодСтенда = читати('аудит/проби/рв6_стенд.js');
    vm.runInContext(кодСтенда.slice(кодСтенда.indexOf('function кінецьПрогону('),
      кодСтенда.indexOf("process.on('exit'")), контекст);
    контекст.кінецьПрогону('повтор записаних викликів', 0);
    результат.стенд.push({сцена: сцена.сцена, rc: код, вердикт: доказ.вердикт(), рядки});
    if (!до && (код < 2 || доказ.вердикт().доведено)) throw new Error('Збій видано за вимір');
  }
  if (!до){
    const контекст = контекстЧату(входи.чат[0]);
    const безКартки = await контекст.підтвердженняКарткиП({відповідь_людині: 'Непідтверджена проза'});
    const рукою = await контекст.підтвердженняКарткиП({хвилини: 59, картка_запиту: {
      година: {значення: 19, джерело: 'hand', уривок: 'стара цитата о 11:00'},
      темп_c: {значення: 18, джерело: 'default'},
      намір: {значення: 'conventional', джерело: 'reading', уривок: 'класика'}}});
    const факти = рукою.запис.вхід.репліка.recorded;
    if (безКартки.текст || рукою.текст || Object.keys(факти).join() !== 'година'
        || факти.година.label !== '19' || факти.година.quote)
      throw new Error('Запасне підтвердження приписало їй непідтверджений факт');
    const прийнята = await контекстЧату(входи.чат[0], JSON.stringify({text: 'Ти збираєшся на вечірку на день народження подруги, субота ввечері.'}))
      .підтвердженняКарткиП(входи.чат[0].паспорт);
    const відхилена = await контекстЧату(входи.чат[0], JSON.stringify({text: 'Ти збираєшся на вечірку о 11-й.'}))
      .підтвердженняКарткиП(входи.чат[0].паспорт);
    if (!прийнята.текст || відхилена.текст || !відхилена.запис.відкинуто?.length)
      throw new Error('Запасний переклад не пройшов суд картки');
    результат.контролі = {безКартки, рукою, прийнята, відхилена,
      джерело_відповідей: 'Синтетичні контролі приймання й відмови; нову модель не викликано.'};
  }
  if (куди){ fs.mkdirSync(куди, {recursive: true});
    fs.writeFileSync(path.join(куди, до ? 'до.json' : 'після.json'), JSON.stringify(результат, null, 1) + '\n'); }
  console.log(JSON.stringify(результат, null, 1));
}
if (require.main === module) main().catch(е => {console.error(е); process.exitCode = 1;});
module.exports = {міст};
