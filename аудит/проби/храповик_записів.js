/* Порівнює кожну звірку й завершення сцени з останнім живим записом. */
const crypto = require('crypto');

function знімок(лог, доказ, rc, застарілий = null) {
  const сталіНазви = new Map([...лог.matchAll(/^  ІД ЗВІРКИ: (.+)\r?$/gm)].map(м => {
    const {назва, стала} = JSON.parse(м[1]);
    return [назва, стала];
  }));
  const повтори = new Map();
  const звірки = [...лог.matchAll(/^  ([✔✗]) (.+?)(?:  →  .*|\r)?$/gm)].map((м) => {
    const назва = м[2].replace(/\r$/, '');
    const стала = сталіНазви.get(назва) || назва;
    const повтор = (повтори.get(стала) || 0) + 1;
    повтори.set(стала, повтор);
    return {ід: crypto.createHash('sha256').update(JSON.stringify([стала, повтор])).digest('hex'),
      назва, зелена: м[1] === '✔'};
  });
  const підсумки = [...лог.matchAll(/^ВПАЛО (\d+) ·/gm)];
  const невраховані = підсумки.length ? Math.max(0, Number(підсумки.at(-1)[1]) - звірки.filter(з => !з.зелена).length) : 0;
  return {версія: 1, завершено: [0, 1].includes(rc) && доказ?.вердикт?.доведено === true && !невраховані,
    rc, звірки, ...(застарілий ? {застарілий} : {})};
}

function звіритиБазу(база) {
  if (база.версія !== 1 || !база.завершено || !Array.isArray(база.звірки) || !база.звірки.length)
    throw new Error('База не має завершеного живого виміру зі звірками');
  if (new Set(база.звірки.map(з => з.ід)).size !== база.звірки.length ||
      база.звірки.some(з => typeof з.зелена !== 'boolean' || !з.ід || !з.назва))
    throw new Error('Пошкоджені чи повторені звірки бази');
  if (база.звірки.some(з => !з.зелена && !/^\d+$/.test(String(з.вада || ''))))
    throw new Error('Червона звірка бази не має номера дошки');
}

function порівняти(база, після) {
  звіритиБазу(база);
  const поточні = new Map(після.звірки.map(з => [з.ід, з]));
  const регресії = база.звірки.filter(з => з.зелена &&
    (поточні.has(з.ід) ? !поточні.get(з.ід).зелена : !після.застарілий)).map(з => з.назва);
  const базові = new Set(база.звірки.map(з => з.ід));
  for (const з of після.звірки)
    if (!з.зелена && !базові.has(з.ід)) регресії.push(з.назва);
  if (!після.завершено && !після.застарілий) регресії.push('сцена не дійшла до кінця');
  const покращення = база.звірки.filter(з => !з.зелена && поточні.get(з.ід)?.зелена).map(з => з.назва);
  return {стан: регресії.length ? 'регрес' : після.застарілий ? 'запис застарів' : 'без регресу',
    регресії, покращення, ...(після.застарілий ? {виклик: після.застарілий.виклик} : {})};
}

function затягнути(база, після) {
  const звіт = порівняти(база, після);
  if (звіт.стан !== 'без регресу') throw new Error('Не можна затягнути базу: ' + звіт.стан);
  const номери = new Map(база.звірки.filter(з => !з.зелена).map(з => [з.ід, з.вада]));
  const нова = {...після, звірки: після.звірки.map(з => ({...з,
    ...(!з.зелена ? {вада: номери.get(з.ід)} : {})}))};
  звіритиБазу(нова);
  return нова;
}

function затягнутиЗелені(база, вимір) {
  звіритиБазу(база);
  // Звірки нового стенда можуть падати на старому main. Вимоги живої бази не послаблюються,
  // а завершений вимір main додає лише доведені зелені: голова мусить їх зберегти.
  if (!вимір.завершено || вимір.застарілий) return база;
  const звірки = new Map(база.звірки.map(з => [з.ід, з]));
  for (const з of вимір.звірки) if (з.зелена) звірки.set(з.ід, {...з});
  const нова = {...база, звірки: [...звірки.values()]};
  звіритиБазу(нова);
  return нова;
}

module.exports = {знімок, звіритиБазу, порівняти, затягнути, затягнутиЗелені};
