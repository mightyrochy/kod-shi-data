"""Рядок 124: кадр збагачення, що стоїть на інших товарах крамниці, більше не є
істиною про цю річ. ДО — правило main (збагачення накладається завжди); ПІСЛЯ —
`фід_каталог` цієї гілки. На весь каталог: скільки кадрів збагачення самі є
спільною картинкою крамниці, скільки записів через це зникло (крамниця не дає
жодного слова кольору) і що саме втратила річ власника `ж-01583@brenda.ua`.
Запуск: python3 аудит/проби/chuzhe_foto_124.py (звідки завгодно)"""
import sys, pathlib, collections
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2] / "джерела"))
import feed as F, фід_каталог as ФК, фід_фото as ФФ
ш = F.каталог_на_диску(); оф = F.читати_yml(ш)[0]; зб = F.читати_збагачення()
сп = ФФ._спільні_фото(оф); мг = lambda o: o.get("магазин") or str(o["id"]).split("@")[-1]
своє = lambda o: [x for x in (o.get("фото") or []) if not ФФ.спільна_картинка(ФФ._файл_фото(x), сп[мг(o)])]
чужі = [o for o in оф if ФФ.чужий_кадр((зб.get(o["id"]) or {}).get("фото"), сп.get(мг(o)) or {})]
_сп = ФК.чужий_кадр; ФК.чужий_кадр = lambda *a, **k: None; ФК._КЕШ_БАЗИ.clear()
до = {r["id"]: r for r in ФК._прочитати_каталог(ш, 0)["каталог"]}
ФК.чужий_кадр = _сп; ФК._КЕШ_БАЗИ.clear()
після = {r["id"]: r for r in ФК._прочитати_каталог(ш, 0)["каталог"]}
ПОЛЯ = ("колір_назва", "колір_за_чим", "крій", "довжина_рівень", "волокно", "візерунок", "блиск")
лиш = [и for и in після if після[и].get("чуже_фото")]
втрати = collections.Counter(п for и in лиш for п in ПОЛЯ
                             if до[и].get(п) not in (None, "") and після[и].get(п) in (None, ""))
print("каталог %s · оферів %d · поріг СПІЛЬНЕ_ФОТО_ТОВАРІВ = %d (різних товарів на файл)"
      % (pathlib.Path(ш).name, len(оф), ФФ.СПІЛЬНЕ_ФОТО_ТОВАРІВ))
print("кадр збагачення САМ є спільною картинкою крамниці: %d оферів (%.1f %%), з них аркою %d"
      % (len(чужі), 100.0 * len(чужі) / len(оф), sum(1 for o in чужі if not своє(o))))
print("   найбільші крамниці:", ", ".join("%s %d" % т for т in collections.Counter(
    мг(o) for o in чужі).most_common(6)))
print("записів каталогу ДО %d · ПІСЛЯ %d (%+d: у них слова кольору не дає ні крамниця, ні фід)"
      % (len(до), len(після), len(після) - len(до)))
print("лишились із названою причиною «чуже_фото»: %d · у них спорожніли поля: %s"
      % (len(лиш), ", ".join("%s %d" % т for т in втрати.most_common()) or "жодного"))
ід = "ж-01583@brenda.ua"
print("\n%s («%s»):" % (ід, (до.get(ід) or {}).get("назва") or "нема в каталозі"))
for п in ПОЛЯ:
    print("   %-16s ДО %-28r ПІСЛЯ %r" % (п, (до.get(ід) or {}).get(п), (після.get(ід) or {}).get(п)))
print("   у каталозі ДО %s · ПІСЛЯ %s · причина: %s" % (ід in до, ід in після, ФФ.ЧОМУ_СПІЛЬНА))
