# -*- coding: utf-8 -*-
"""Е3-одна-величина ч19 (п.6): ДО → ПІСЛЯ — посадка (K-FIT-03), зони (ярлик A/V), пропорції й припуск.

Запуск із кореня репозиторію:
    python3 аудит/проби/Е3_ч19_каталог.py                        # ПІСЛЯ: код цієї гілки
    git worktree add /tmp/до <SHA_ДО>
    python3 аудит/проби/Е3_ч19_каталог.py --код /tmp/до/джерела   # ДО: той самий скрипт на старому коді

Каталог — `джерела/каталог_повний.xml` цього клону (один для ДО й ПІСЛЯ) через `bridge.виклик("запити")`;
модель і платні API не кличуться. Перебір: крої верх × низ на тілі стенда й трьох тілах. Друкує:
  1. зони: ярлик (`fit.зони`) на чотирьох тілах;
  2. K-FIT-03 (`fit.краї`): краї низу з кроком 2 см — лічба за силою знахідки;
  3. K-SIL-03 «обʼєм без якоря» і види якорів (`силует_пропорції.якорі`) через `силует_запит.перевірити`."""
import sys, pathlib, json, collections, os, io, contextlib, itertools

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
код = pathlib.Path(sys.argv[sys.argv.index("--код") + 1]).resolve() if "--код" in sys.argv else КОРІНЬ / "джерела"
os.chdir(код); sys.path.insert(0, str(код))
import feed as Ф, bridge as B, outfit as O, silhouette as СЛ, composer as КМ, fit as ПС

print(f"код: {код}")
вх = json.load(open(код / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску(str(КОРІНЬ / "джерела" / "каталог_повний.xml")); вх["гілка"] = 0
with contextlib.redirect_stdout(io.StringIO()):
    json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
_F, T_стенд, _зр, _kw = B._збірка(вх)
за = collections.defaultdict(list)
for c in кат:
    к = O.крій_речі(c)
    if к: за[(c.get("слот"), к)].append(c)
ТІЛА = [("стенд", T_стенд)] + [(п, ПС.тіло(зр, обх)) for п, зр, обх in (
    ("пісочний", 168, dict(плечі=98, груди=92, талія=72, стегна=100)),
    ("яблуко", 160, dict(плечі=104, груди=104, талія=88, стегна=112)),
    ("трикутник", 170, dict(плечі=100, груди=96, талія=84, стегна=104)))]
верхи = sorted(k for k in за if k[0] == "верх"); низи = sorted(k for k in за if k[0] == "низ")

print("\n1. ЗОНИ: ярлик")
for п, T in ТІЛА:
    з = ПС.зони(T)
    print(f"   {п:10s} ярлик {з['ярлик']}")

print("\n2. K-FIT-03: край низу від 0 до зросту, крок 2 см (низ з явною довжиною: верх = талія), `fit.краї`")
for п, T in ТІЛА:
    H = T["висоти"]; відп = collections.Counter()
    for край_см in range(2, int(T["зріст"] * 0.55), 2):
        річ = dict(id="н", слот="низ", крій="regular", верх_см=H["талія"], низ_см=float(край_см))
        зн = ПС.краї(T, [річ])
        відп[("питання" if not зн else "; ".join(sorted({f'{z["сила"]}' for z in зн})))] += 1
    print(f"   {п:10s} {dict(sorted(відп.items()))}")

print(f"\n3. K-SIL-03 і види якорів: крої каталогу верх {len(верхи)} × низ {len(низи)} × тіл {len(ТІЛА)}")
for п, T in ТІЛА:
    сил03, види = 0, collections.Counter()
    for (_, кв), (_, кн) in itertools.product(верхи, низи):
        речі = [КМ.у_річ(dict(за[("верх", кв)][0]), "верх", T), КМ.у_річ(dict(за[("низ", кн)][0]), "низ", T)]
        for z in СЛ.перевірити(T, речі, intent="conventional", мета="лестити"):
            if z["правило"] == "K-SIL-03": сил03 += 1
        for я in __import__("силует_пропорції").якорі(СЛ.обгортка(T, речі), T):
            види[я["вид"].split()[0]] += 1
    print(f"   {п:10s} K-SIL-03 {сил03}; якорі {dict(види)}")
