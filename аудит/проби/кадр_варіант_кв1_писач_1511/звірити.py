"""Звіряє весь повтор із виміром 14.11, окремо відділяючи зміну читача на main."""
import argparse
import collections
import csv
import gzip
import hashlib
import json
from pathlib import Path
import sys
from urllib.parse import urlsplit

ТЕКА = Path(__file__).resolve().parent
КОРІНЬ = ТЕКА.parents[2]
sys.path.insert(0, str(КОРІНЬ / "джерела"))
import фід_власник_кадру as читач


def читати(шлях):
    """Читає звіт, відхиляючи повторний id."""
    with gzip.open(шлях, "rt", encoding="utf-8") as потік:
        рядки = [json.loads(р) for р in потік]
    записи = {р["ід"]: р for р in рядки}
    assert len(рядки) == len(записи) == 13882
    return записи


def таблиця(шлях, поля, рядки):
    """Пише таблицю UTF-8 із стабільними переносами рядків."""
    with шлях.open("w", encoding="utf-8", newline="") as потік:
        запис = csv.writer(потік, delimiter="\t", lineterminator="\n")
        запис.writerow(поля)
        запис.writerows(рядки)


def main():
    """Перераховує всі докази кожного кадру й переходи причин за крамницями."""
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("--після", type=Path, required=True)
    а = парсер.parse_args()
    шлях_до = ТЕКА.parent / "кадр_варіант_кв1_канал_1411" / "результати.jsonl.gz"
    до = читати(шлях_до)
    після = читати(а.після / "результати.jsonl.gz")
    assert до.keys() == після.keys()
    лічби = collections.defaultdict(collections.Counter)
    зміни = []
    for ід, старий in до.items():
        новий = після[ід]
        assert старий["адреса"] == новий["адреса"]
        assert (старий["код"], старий["кінцева_адреса"]) == (новий["код"], новий["кінцева_адреса"])
        assert новий["стан"] not in ("збій_розбору", "не_виміряно")
        л = лічби[urlsplit(новий["адреса"]).netloc]
        л["записів"] += 1
        л["нема_id_ДО"] += старий.get("причина") == "нема_id"
        л["нема_id_ПІСЛЯ"] += новий.get("причина") == "нема_id"
        л["нема_id_ДО_усі"] += "нема_id" in старий.get("причини", [])
        л["нема_id_ПІСЛЯ_усі"] += "нема_id" in новий.get("причини", [])
        л["доведено_ДО_історично"] += старий["стан"] == "доведено"
        л["доведено_ПІСЛЯ"] += новий["стан"] == "доведено"
        л["без_відповіді"] += новий["стан"] == "без_відповіді"
        чинний_до = False
        for р in (старий, новий):
            з = р.get("запис")
            if з is None:
                continue
            докази = [читач.доказ_варіанта(з, к) for к in з["фото"]]
            прийнято = bool(докази) and all(докази)
            if р is старий:
                чинний_до = прийнято
                л["доведено_ДО_чинний_читач"] += прийнято
            else:
                assert прийнято == (р["стан"] == "доведено"), ід
                assert докази == р["докази"], ід
                # Власні фікстури не замінюють доказ із поточних фактів кожного кадру.
                л["прийнятих_кадрів"] += sum(bool(д) for д in докази)
        л["втрачено_доказів"] += чинний_до and новий["стан"] != "доведено"
        if чинний_до:
            assert set(старий["запис"]["фото"]) <= set(новий["запис"]["фото"]), ід
            assert all(читач.доказ_варіанта(новий["запис"], к) for к in старий["запис"]["фото"]), ід
        було = старий.get("запис", {}).get("параметри", {}).get("id_магазину")
        стало = новий.get("запис", {}).get("параметри", {}).get("id_магазину")
        л["без_id_у_записі_ДО"] += "запис" in старий and not було
        л["без_id_у_записі_ПІСЛЯ"] += "запис" in новий and not стало
        if було != стало:
            зміни.append([ід, новий["адреса"], було or "", стало or "", старий["стан"], новий["стан"]])
    разом = sum(лічби.values(), collections.Counter())
    assert разом["нема_id_ДО"] == 7408 and разом["доведено_ДО_історично"] == 21
    assert разом["втрачено_доказів"] == 0, разом
    поля = ["записів", "нема_id_ДО", "нема_id_ПІСЛЯ", "нема_id_ДО_усі", "нема_id_ПІСЛЯ_усі",
            "доведено_ДО_історично", "доведено_ДО_чинний_читач", "доведено_ПІСЛЯ",
            "втрачено_доказів", "прийнятих_кадрів", "без_відповіді",
            "без_id_у_записі_ДО", "без_id_у_записі_ПІСЛЯ"]
    таблиця(ТЕКА / "порівняння.tsv", ["крамниця"] + поля,
            [[д] + [лічби[д][п] for п in поля] for д in sorted(лічби)] +
            [["РАЗОМ"] + [разом[п] for п in поля]])
    таблиця(ТЕКА / "зміни_id.tsv", ["ід", "адреса", "id_ДО", "id_ПІСЛЯ", "стан_ДО", "стан_ПІСЛЯ"], sorted(зміни))
    (ТЕКА / "лічба.tsv").write_bytes((а.після / "лічба.tsv").read_bytes())
    звірка = dict(разом={п: разом[п] for п in поля}, змін_id=len(зміни), sha256={
        назва: hashlib.sha256(шлях.read_bytes()).hexdigest() for назва, шлях in
        (("результати_ДО.jsonl.gz", шлях_до), ("лічба.tsv", а.після / "лічба.tsv"),
         ("результати_ПІСЛЯ.jsonl.gz", а.після / "результати.jsonl.gz"))})
    # Для повторної перевірки читача досить запису й доказів; повний розбір відтворює повтор.py.
    стислий = "".join(json.dumps({к: в for к, в in після[ід].items() if к not in ("факти", "канонічний")},
                               ensure_ascii=False, sort_keys=True) + "\n" for ід in sorted(після))
    архів = ТЕКА / "результати.jsonl.gz"
    архів.write_bytes(gzip.compress(стислий.encode("utf-8"), mtime=0))
    звірка["sha256"]["результати_стислі.jsonl.gz"] = hashlib.sha256(архів.read_bytes()).hexdigest()
    (ТЕКА / "звірка.json").write_text(json.dumps(звірка, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(звірка, ensure_ascii=False), flush=True)


if __name__ == "__main__":
    main()
