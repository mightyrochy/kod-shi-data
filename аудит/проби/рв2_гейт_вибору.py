# РВ-2 З-4: гейт вибору у Python (Т-06) пропускає образ «сукня + низ», який структура
# називає подвоєнням: `_код_блокера` перекладає «подвоєн…» у `слот_двічі`, а
# `_склад_вибору` скидає `слот_двічі` без другої речі в слоті. Старий JS-гейт цей
# рядок ловив. Без каталогу, за секунду. Запуск: python3 аудит/проби/рв2_гейт_вибору.py
import sys, os, json, re
ДЖ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "джерела")
sys.path.insert(0, ДЖ)
import pipeline as PL

канд = {"сукня": [dict(id="с-1@к.ua", назва="сукня міді", слот="сукня")],
        "низ": [dict(id="н-1@к.ua", назва="спідниця олівець", слот="низ")],
        "взуття": [dict(id="в-1@к.ua", назва="човники", слот="взуття")]}
ном = PL.номери_речей(канд)[0]; н = lambda і: "#%d·%s" % ном[і]
рядок = "«сукня» і «низ» разом — низ подвоєний: лиши сукню або лиши низ"     # слово в слово з структура_образу
речі = [dict(id=і, слот=к, назва=канд[к][0]["назва"]) for к, і in (("сукня", "с-1@к.ua"), ("низ", "н-1@к.ua"), ("взуття", "в-1@к.ua"))]
блокери = PL.блокери_структури([рядок], речі, ном)
print("код блокера: %s → блокери_структури %s" % (PL._код_блокера(рядок), блокери))
вердикт = dict(версія="1", ітерація=2, образи=[
    dict(ід="о1", речі=[н("с-1@к.ua"), н("н-1@к.ua"), н("в-1@к.ua")], структура=dict(ок=False, блокери=блокери)),
    dict(ід="о2", речі=[н("с-1@к.ua"), н("в-1@к.ua")], структура=dict(ок=True, блокери=[]))],
    завдання=dict(образів=1, відповідь="ВИБІР_V1"))
в = PL.вибір_з_json(json.dumps(dict(версія="1", обрано="о1", чому="хочу і сукню, і спідницю")), вердикт, кандидати=канд)
print("ВИБІР_V1 «о1» (сукня+низ, блокер у структурі): прийнято ід=%s · замінено=%s · чому_відмова=%s"
      % (в["ід"], в["замінено"], в["чому_відмова"]))
в2 = PL.вибір_з_json(json.dumps(dict(версія="1", обрано="о1", прибрати=[н("н-1@к.ua")])), вердикт, кандидати=канд)
print("…з «прибрати» спідницю: ід=%s · прибрано=%s · знехтувано=%s" % (в2["ід"], в2["прибрано"], [x["чому"] for x in в2["знехтувано"]]))
print("старий гейт JS (до Т-06) ловив цей рядок:",
      bool(re.search(r"по одній на слот|аксесуари, а не образ|подвоєн|з однієї речі", рядок)))
