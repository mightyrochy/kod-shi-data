/* Лічба доставки — цілими питаннями, до окремої перевірки мови показу. */
const assert = require('node:assert/strict');
const {питаньЗВідповіддю, перекладШару} = require('./записи_шару.js');
const запис = заяви => ({напрям: 'out_messages', де: 'hand_1.code_unknowns', заяви});
const заява = (ключ, стан, текст) => ({повідомлення: 'питання.0', ключ, стан, текст});
const перший = запис([заява('а', 'translated', 'Речення.'), заява('б', 'missing_text', '')]);
assert.equal(питаньЗВідповіддю([перший]), 0);
const повтор = запис([заява('б', 'foreign_language', 'A sentence.')]);
assert.equal(питаньЗВідповіддю([перший, повтор]), 1);
assert.equal(питаньЗВідповіддю([перший, повтор, повтор]), 1);
assert.equal(перекладШару(повтор, 'б'), undefined); // жінці чужомовне не прийнято
assert.equal(питаньЗВідповіддю([запис([заява('а', 'latin_remainder', 'Речення з latin.')])]), 1);
assert.equal(питаньЗВідповіддю([запис([заява('а', 'missing_text', 'Запасний текст.')])]), 0);
console.log('Доставка заяв, неповне питання, повтор, чужомовна відповідь і мовний сторож — гаразд');
