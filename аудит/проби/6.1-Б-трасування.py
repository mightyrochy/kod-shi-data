"""Зіставляє записаний ланцюг серії 1 з поточним розбором її мовних відповідей; без моделей і мережі."""
import json
import re
import sys
from pathlib import Path

КОРІНЬ = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(КОРІНЬ / "джерела"))
import мовний_шар as М
import паспорт_нагоди as П
import сценарій as С
import пакет_моделі as ПМ
import дріт_моделі as Д
# Фасад bridge не експортує читач випадку ремонту й вибору.
from міст_відповіді import _випадок_кодами


def виміряти():
    """Друкує факти проходження наявних відповідей; це не живий ПІСЛЯ і не оцінка доречності."""
    рядки = []
    for тека in sorted((КОРІНЬ / "аудит/проби/б1/ДО-2610").glob("*/повтор*/VIDPOVIDI")):
        записи = []
        for файл in (ф for ф in sorted(тека.glob("*.txt")) if any(к in ф.name for к in ("хід_розмови", "ПАКЕТ", "ВЕРДИКТ"))):
            текст = файл.read_text(encoding="utf-8")
            запис = re.fullmatch(r"── ПРОМПТ \(\d+ симв\.\) ──\n(.*)\n\n── ВІДПОВІДЬ \([^\n]*\) ──\n(.*)\n", текст, re.S)
            if запис:
                записи.append((файл.name, json.JSONDecoder().raw_decode(запис[1])[0], запис[2]))
        назва, вхід, відповідь = next(з for з in записи if "хід_розмови" in з[0])
        розбір = М.прийняти_розмову(відповідь)
        паспорт = М.паспорт_з_шару(розбір["внутрішня"], {}, слова_ходу=вхід["her_new_message"],
                                  частини=розбір["частини"], не_взято=розбір["не_взято"])["паспорт"]
        сцена, _ = П.з_показу({}, паспорт)
        випадок = ПМ.випадок_для_пакета(паспорт, "", сцена)
        день = С.день_кодами(сцена)
        дріт = Д.випадок(випадок, день)
        суд = _випадок_кодами({"пакет": {"випадок": випадок}}, {"day": Д.день_на_дріт(день)})
        етапи = [{"файл": н, "випадок": в.get("case"),
                  "день": {к: в.get("day", {}).get(к) for к in ("start_hour", "part_of_day", "movement")}}
                 for н, в, _ in записи if any(к in н for к in ("ПАКЕТ", "ВЕРДИКТ"))]
        рядки.append(dict(сцена=тека.parent.parent.name, повтор=тека.parent.name, запит=вхід["her_new_message"],
                           мовний_виклик=назва, поточний_розбір=розбір["внутрішня"],
                           незнайомі=розбір["незнайомі"], подія=паспорт.get("подія"),
                           поточний_випадок=дріт, поточний_ремонт_і_вибір=суд,
                           день=С.день_кодами(сцена), записані_етапи=етапи))
    print(json.dumps(рядки, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    виміряти()
