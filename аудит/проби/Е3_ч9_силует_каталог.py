# -*- coding: utf-8 -*-
"""Е3-одна-величина ч9 (п.2, силует): каталог ДО → ПІСЛЯ за кожним зміненим порівнянням.

Запуск із кореня репозиторію:
    python3 аудит/проби/Е3_ч9_силует_каталог.py                       # ПІСЛЯ: код цієї гілки
    git worktree add /tmp/до <SHA_ДО>
    python3 аудит/проби/Е3_ч9_силует_каталог.py --код /tmp/до/джерела  # ДО: той самий скрипт на старому коді

Каталог — `джерела/каталог_повний.xml` цього клону (один і той самий для ДО й ПІСЛЯ), через живий
`bridge.виклик("запити")` стенда; модель і платні API не викликаються. Перебір: усі крої каталогу
верх × низ (перший запис кожного крою, `composer.у_річ`) на тілі стенда й трьох тілах гейтів.
Друкує по кожному зміненому порівнянню:
  K-SIL-01 (`конкуренція`, поріг `виразність_відльоту`) — лічба за силою;
  K-BOD-02 (`нічия_стратегія` — пороги `втягнення_H`, `розкид_контуру_колони`, `розкид_колони`;
            `зонні_операції` — масштаб `повна_операції_см`) — лічба за (сила, заява);
  літера образу (`колона`, `skim_стеля`) — лічба літер;
  гіперребра тіла (`баланс_пари` — бік перекосу за 0.10; `одна_лінія` — рампа `розкид_профілю_повний`)
            і ранжування кроїв пулу (`крої_для_пулу`, `влучання`)."""
import sys, pathlib, json, collections, os, io, contextlib

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
код = pathlib.Path(sys.argv[sys.argv.index("--код") + 1]).resolve() if "--код" in sys.argv else КОРІНЬ / "джерела"
os.chdir(код); sys.path.insert(0, str(код))
import feed as Ф, bridge as B, outfit as O, silhouette as СЛ, composer as КМ, fit as ПС, hypergraph as ГГ

вх = json.load(open(код / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску(str(КОРІНЬ / "джерела" / "каталог_повний.xml")); вх["гілка"] = 0
with contextlib.redirect_stdout(io.StringIO()):
    json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
F, T_стенд, _зр, _kw = B._збірка(вх)
за = collections.defaultdict(list)
for c in кат:
    к = O.крій_речі(c)
    if к: за[(c.get("слот"), к)].append(c)
ТІЛА = [("стенд", T_стенд)] + [(п, ПС.тіло(зр, обх)) for п, зр, обх in (
    ("пісочний", 168, dict(плечі=98, груди=92, талія=72, стегна=100)),
    ("яблуко", 160, dict(плечі=104, груди=104, талія=88, стегна=112)),
    ("трикутник", 170, dict(плечі=100, груди=96, талія=84, стегна=104)))]
верхи = sorted(k for k in за if k[0] == "верх"); низи = sorted(k for k in за if k[0] == "низ")
print(f"код: {код}  · кроїв каталогу верх {len(верхи)} × низ {len(низи)} × тіл {len(ТІЛА)}")

сіл01, бод02, літ = collections.Counter(), collections.Counter(), collections.Counter()
комбінацій = 0
for підпис, T in ТІЛА:
    for (_, кв) in верхи:
        for (_, кн) in низи:
            речі = [КМ.у_річ(dict(за[("верх", кв)][0]), "верх", T), КМ.у_річ(dict(за[("низ", кн)][0]), "низ", T)]
            комбінацій += 1
            літ[СЛ.літера(СЛ.обгортка(T, речі)).get("літера")] += 1
            for z in СЛ.перевірити(T, речі, intent="conventional", мета="лестити"):
                коди = tuple(sorted({з["code"] for з in (z.get("заяви") or [])
                                     if з["code"] != "cut_not_declared_assumed_regular"}))
                if z["правило"] == "K-SIL-01": сіл01[z["сила"]] += 1
                if z["правило"] == "K-BOD-02": бод02[(z["сила"], коди)] += 1
print(f"комбінацій: {комбінацій}")
print("K-SIL-01 за силою:", dict(sorted(сіл01.items())))
print("K-BOD-02 за (сила, заяви):")
for (с, к), n in sorted(бод02.items(), key=lambda x: (-x[1], x[0])): print(f"   {n:5d}  {с:9s} {', '.join(к) or '—'}")
print("літера образу:", dict(sorted(літ.items(), key=lambda x: str(x[0]))))
print("гіперребра тіла:")
for підпис, T in ТІЛА:
    р = {е["ід"]: е for е in ГГ.ребра(T)}
    бп, ол = р.get("баланс_пари"), р.get("одна_лінія")
    print(f"   {підпис:10s} баланс_пари: {бп and бп['рядок'][:110]!r}")
    print(f"   {'':10s} одна_лінія: напруга {ол and ол['напруга']}; заяви {[з['code'] for з in (ол or {}).get('заява') or []]}")
    пул = ГГ.крої_для_пулу(T)
    print(f"   {'':10s} ярус кроїв пулу: " + "; ".join(
        f"{сл} {sorted(в.get('ярус') or [])}" for сл, в in sorted(пул.items()) if isinstance(в, dict)))
