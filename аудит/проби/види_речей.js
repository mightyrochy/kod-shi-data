/* КОРОТКИЙ ЗАПИС РЕЧІ (К-3, 27.09.2026) читається тим самим словником. У ньому тип речі
   зветься `item_type` (код мовної моделі з тієї самої таблиці, що й `type`), а назви
   крамниці нема зовсім — її заміняє англійський рядок особливостей `features`. Заглушка
   мусить це розуміти: без цього рядка стенд з увімкненим перемикачем зібрав увесь пул
   (309 речей) в один вид «інше» і руки 1–2 не склали жодного образу — тобто прилад міряв
   свою сліпоту, а не продукт. Справжня модель обидва ключі читає однаково. */
function видРечі(р){
  /* `ty` — короткий ключ типу речі в короткому записі; що він означає, каже шапка промпта
     (`pool_keys`, `дріт_моделі.ЗНАЧЕННЯ_КЛЮЧІВ`), і справжня модель читає його звідти.
     Заглушка словника не має — тому три імені того самого факту перелічені тут.
     Без цього рядка стенд з увімкненими обома перемикачами (короткий запис + частини) зібрав
     увесь пул в один вид «інше», і руки 1–2 не склали жодного образу. */
  const тип = р.type || р.item_type || р.ty;
  for (const [вид, типи] of Object.entries(ВИД_ТИПУ)) if (типи.includes(тип)) return вид;
  for (const [рег, вид] of ВИД_НАЗВИ) if (рег.test(р.name || р.features || р.fe || '')) return вид;
  return 'інше';
}
/* пул за видами: український пакет (main) — як є; англійський перелік — за `видРечі` */
function пулЗаВидами(об){
  if (об.пул) return об.пул;
  const п = {};
  for (const р of (об.pool || [])) { const в = р.two_piece ? 'комплект' : видРечі(р); (п[в] = п[в] || []).push({...р, н: р.n, назва: р.name || р.fe || р.features}); }
  return п;
}
