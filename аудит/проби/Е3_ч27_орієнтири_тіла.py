"""Е3-одна-величина ч27 (п.7, орієнтири тіла): рівні профілю й вікна імен орієнтирів брифу на тілах 155/165/175 см.

Запуск із кореня репозиторію:
    python3 аудит/проби/Е3_ч27_орієнтири_тіла.py                       # ПІСЛЯ: код цієї гілки
    git worktree add /tmp/до <SHA_ДО>
    python3 аудит/проби/Е3_ч27_орієнтири_тіла.py --код /tmp/до/джерела  # ДО: той самий скрипт на старому коді

Друкує: (1) висоти рівнів `fit.тіло(зріст, обхвати стенда)["висоти"]`; (2) для кожного зросту — вікна висот від підлоги
(крок 0.1 см), у яких `brief.орієнтир` дає те саме ім'я: ім'я, від, до (см), код заяви; (3) питання про обхват литки.
Каталог і модель не викликаються."""
import sys, pathlib, os

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
код = pathlib.Path(sys.argv[sys.argv.index("--код") + 1]).resolve() if "--код" in sys.argv else КОРІНЬ / "джерела"
os.chdir(код); sys.path.insert(0, str(код))
import fit as ПС, brief as Б, profile as ПР

print(f"код: {код}")
ТІЛА = {зр: ПС.тіло(зр, dict(плечі=98, груди=92, талія=74, стегна=100)) for зр in (155, 165, 175)}
for зр, т in ТІЛА.items():
    print(f"висоти рівнів {зр} см:", ", ".join(f"{н} {round(в, 1)}" for н, в in sorted(т["висоти"].items(), key=lambda x: -x[1])))
for зр, т in ТІЛА.items():
    H, вікна, пред, поч = т["висоти"], [], None, 0
    for i in range(0, int(зр * 10) + 1):
        н = Б.орієнтир(H, i / 10)
        if н != пред:
            if пред is not None:
                вікна.append((пред, поч / 10, (i - 1) / 10))
            пред, поч = н, i
    вікна.append((пред, поч / 10, зр))
    print(f"вікна імен орієнтирів {зр} см (ім'я: від–до, см від підлоги):")
    for н, a, b in вікна:
        print(f"   {н}: {a:.1f}–{b:.1f}")
print("питання про обхват литки:", ПР.ТІЛО_ПИТАННЯ["обхват_литки_см"]["питання"])
