import unittest

import режими_рядків_pr as р

ІД = "ж9_вечеря_без_пальта"


class РежимФункція(unittest.TestCase):
    def причина(self, режим):
        return р.перевірити([{"id": ІД, "question": f"контроль K-KOH-05 → {режим} → — → K-KOH-05 є", "line": ""}])[0][2]

    def test_функція_приймається(self):
        self.assertIsNone(self.причина("функція"))

    def test_повне_приймається(self):
        self.assertIsNone(self.причина("повне"))

    def test_невідомий_режим_вада(self):
        self.assertIn("невідом", self.причина("довільна інструкція"))

    def test_функція_із_змінною_стенда_лишається_хмарною(self):
        self.assertIsNone(self.причина("функція, FOTO=1"))


if __name__ == "__main__":
    unittest.main()
