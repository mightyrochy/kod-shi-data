        к = контексти[р['id']]
        причина = None
        if р.get('стан') != 200:
            причина = 'HTTP ' + str(р.get('стан')) + '; ' + р.get('помилка', '')
        elif not к.get('після_h1', '').strip():
            причина = 'HTTP 200, але немає тексту товарної сторінки після вилучення script/style'
        else:
            доступ[к['крамниця']] += 1
