    тека = КОРІНЬ / 'аудит/проби/річ_запис_каталог_2026_10_30'
    def json_файл(імя):
        """Прочитати один зафіксований JSON."""
        return json.loads((тека / імя).read_text(encoding='utf-8'))
    def рядки(імя):
        """Прочитати всі рядки стисненого протоколу."""
        return [json.loads(р) for р in gzip.decompress((тека / імя).read_bytes()).decode().splitlines()]
