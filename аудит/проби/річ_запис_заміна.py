"""Підібрати замінники непридатним сторінкам вибірки п.3 (той самий магазин, наступні за порядком).

Запуск із кореня: python -X utf8 аудит/проби/річ_запис_заміна.py ТЕКА ВХІД.json
ТЕКА — каталог проби; ВХІД.json — [{id, url}] непридатних сторінок. Пише ТЕКА/кандидати.json:
для кожної непридатної — до 5 наступних унікальних URL тієї ж крамниці у відсортованому порядку
(по колу), що ще не в вибірці; поля фіда беруться з каталогу тим самим читачем, що й вибірка.
"""
import json
import sys
from pathlib import Path

from річ_запис_каталог import офери, поля_вибірки, записати


def main():
    """Скласти кандидатів-замінників без мережі."""
    тека, вхід = Path(sys.argv[1]), Path(sys.argv[2])
    вибірка = json.loads((тека / 'вибірка.json').read_text(encoding='utf-8'))
    зайняті = {р['url'] for р in вибірка}
    непридатні = json.loads(вхід.read_text(encoding='utf-8'))
    за_крамницею = {}
    for о in sorted(офери('каталог_повний.xml.gz'), key=lambda о: о['id']):
        за_крамницею.setdefault(о['магазин'], {}).setdefault(о['url'], о)
    результат = []
    for н in непридатні:
        крамниця = next(р['крамниця'] for р in вибірка if р['url'] == н['url'])
        адреси = sorted(за_крамницею[крамниця])
        початок = адреси.index(н['url'])
        порядок = [адреси[(початок + к) % len(адреси)] for к in range(1, len(адреси))]
        кандидати = []
        for url in порядок:
            if url in зайняті or url in {к['url'] for р in результат for к in р['кандидати']}:
                continue
            о = за_крамницею[крамниця][url]
            кандидати.append(dict(id=о['id'], крамниця=крамниця, url=url, назва=о['назва'], опис=о.get('опис'),
                склад=о['параметри'].get('склад'), розділ=о['параметри'].get('категорія_магазину') or о['категорія']))
            if len(кандидати) == 5:
                break
        результат.append(dict(замість=н['url'], крамниця=крамниця, кандидати=поля_вибірки(кандидати)))
    записати(тека / 'кандидати.json', результат)
    print('кандидатів:', sum(len(р['кандидати']) for р in результат))


if __name__ == '__main__':
    main()
