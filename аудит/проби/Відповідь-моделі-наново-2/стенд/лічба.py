#!/usr/bin/env python3
"""Мірило наряду Відповідь-моделі-наново, крок 2, на записах стенда: по кожній картці (ситуація · прохід · рука).

Запуск з кореня репозиторію: python3 аудит/проби/Відповідь-моделі-наново-2/стенд/лічба.py до після
Джерело — `<до|після>/<ситуація>/verdykty-*.json.gz` (вивантаження вердиктів сторінки, яке стенд робить сам; екрани — `<до|після>/стенд/службове/<с>/екрани.jsonl.gz`): склад
картки (`склад`), опис картки (`етапи.суд.опис`: `про_речі` з id речі, `текст`, `як_носити`) і діагноз руки.
Лічить:
- «заміну оголошено, не зроблено» — текст опису на картці каже про заміну (swap / replac / заміню / замінюю),
  а діагноз руки не має `photo_swap_card · swap=applied`;
- «твердження про річ поза складом» — абзац `про_речі` з id, якого нема в складі картки, чи
  `description_named_not_in_outfit` / `description_template` у діагнозі без переписаного тексту;
- «`склад_картки` = склад на картці» — поле кроку 3 (лише ПІСЛЯ; «—» — поля нема) називає ті самі речі, що картка;
- «порада називає річ складу» — картка, у якої є абзац `про_речі` з id речі складу й непорожнім текстом
  (руки 3–4 без каталогу абзаців `про_речі` не мають — для них: непорожній опис).
"""
import glob
import gzip
import json
import os
import re
import sys

ТУТ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ЗАМІНА = re.compile(r"\b(swap|swapp|replac)|заміню|замінюю|заміняю|заміна сукні", re.I)


def картки(тека):
    for ф in sorted(glob.glob(os.path.join(ТУТ, тека, "*", "verdykty-*.json.gz"))):
        сит = os.path.basename(os.path.dirname(ф))
        с = сит.split("_")[0]
        д = json.load(gzip.open(ф, "rt", encoding="utf-8"))
        екрани = [json.loads(л) for л in gzip.open(os.path.join(ТУТ, тека, "стенд", "службове", сит, "екрани.jsonl.gz"),
                                                     "rt", encoding="utf-8")]
        for н, п in enumerate(д["прогони"], 1):
            for в in п["вердикти"]:
                yield с, н, в, (тека + "/" + сит, екрани)


def кадр(в, н, де):
    """Перший знімок проходу, на якому видно початок опису картки (`знімки/NNNN.jpg` — крок екрана)."""
    тека, екрани = де
    почин = " ".join(str(в.get("опис") or "").split())[:60]
    if not почин:
        return "—"
    for е in екрани:
        if е.get("прохід") == н and почин in " ".join(str(е.get("текст") or "").split()):
            return "[%04d](%s/знімки/%04d.jpg)" % (е["крок"], тека, е["крок"])
    return "—"


def лічити(тека):
    рядки, сума = [], dict(карток=0, заміна_не_зроблена=0, поза_складом=0, порада_про_склад=0, склад_картки_інший=0)
    for с, н, в, де in картки(тека):
        склад = set((в.get("склад") or "").split("+")) - {""}
        оп = (в.get("етапи") or {}).get("суд", {}).get("опис") or {}
        діаг = (в.get("етапи") or {}).get("діагноз_руки") or []
        текст = " ".join([str(оп.get("текст") or ""), " ".join(оп.get("як_носити") or []), str(в.get("опис") or "")])
        застосовано = any("photo_swap_card · swap=applied" in д for д in діаг)
        запропоновано = [д.split("photo_swap_proposed · ")[1][:80] for д in діаг if "photo_swap_proposed" in д]
        не_зроблено = bool(ЗАМІНА.search(текст)) and not застосовано
        поза = [р.get("id") for р in оп.get("про_речі") or [] if р.get("id") and р.get("id") not in склад]
        поза += [д.split(" · ")[1][:80] for д in діаг if "named_not_in_outfit" in д and "card=template" not in д]
        про_склад = (any(р.get("id") in склад and (р.get("текст") or "").strip() for р in оп.get("про_речі") or [])
                     or (в.get("рука") in ("3", "4") and bool(str(в.get("опис") or "").strip())))
        ск = ((в.get("етапи") or {}).get("суд") or {}).get("склад_картки")
        ск_рядок = "—" if ск is None else ("=" if set(ск.get("ід") or []) == склад else "**≠**")
        сума["склад_картки_інший"] += ск_рядок == "**≠**"
        сума["карток"] += 1
        сума["заміна_не_зроблена"] += не_зроблено
        сума["поза_складом"] += bool(поза)
        сума["порада_про_склад"] += про_склад
        рядки.append(f"| {с} · {н} · рука {в.get('рука')} | {len(склад)} | "
                     f"{'; '.join(запропоновано) or '—'} | {'так' if застосовано else '—'} | "
                     f"{'**так**' if не_зроблено else '—'} | {', '.join(map(str, поза)) or '—'} | "
                     f"{'так' if про_склад else '**ні**'} | {ск_рядок} | {кадр(в, н, де)} |")
    return рядки, сума


if __name__ == "__main__":
    for тека in sys.argv[1:] or ["до", "після"]:
        рядки, сума = лічити(тека)
        print(f"\n### {тека}\n\n| картка | речей | заміну запропоновано | заміну застосовано | оголошено, не зроблено "
              "| твердження поза складом | порада про річ складу | `склад_картки` = склад на картці | кадр |"
              "\n|---|---|---|---|---|---|---|---|---|")
        print("\n".join(рядки))
        print(f"\n{тека}: " + " · ".join(f"{к} {в}" for к, в in сума.items()))
