def назви(набір):
    """40 назв набору в порядку номерів (sproba2 — лише речі мірила 1–40, без запасних)."""
    with open(ОГЛЯД / "назви.tsv", encoding="utf-8") as ф:
        рядки = [р for р in csv.DictReader(ф, delimiter="\t") if р["набір"] == набір and int(р["номер"]) <= 40]
    if len(рядки) != 40:
        raise ValueError(f"{набір}: {len(рядки)} назв замість 40")
    return [(int(р["номер"]), р["назва"]) for р in рядки]


