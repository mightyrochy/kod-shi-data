def запит_мотиву(набір):
    """Запит кроку 5: ті самі 40 назв, без переліку класів продукту."""
    перелік = "\n".join(f"{н}. {назва}" for н, назва in назви(набір))
    return f"{МОТИВ}\nНазви:\n{перелік}\n"


def словник():
    """Той самий довідник «номер: назва_uk», що бачила мала модель спроби 6 (чинний шлях вибору)."""
    with open(КОДУЄ / "словник_iscc_267.tsv", encoding="utf-8") as ф:
        return "\n".join(f"{р['код']}: {р['назва_uk']}" for р in csv.DictReader(ф, delimiter="\t"))


def опори():
    """Опорні точки шкал LCh для (В): нейтральні N1–N9.5, десять основних тонів на V6/C6, хрома 5YR V6.

    Рахує те саме пряме перетворення renotation C → Bradford → Lab D65, що й межі блоків; під свотчі не підібрано."""
    sys.path.insert(0, str(КОДУЄ))
    sys.path.insert(0, str(КОРІНЬ / "джерела"))
    import блоки
    from колір_простір_перетворення import lch
    пряме = блоки.ПЕРЕНОС.зробити_перетворення(блоки.бібліотека())
    L = lambda H, V, C: lch(пряме(H, V, C)[0])
    нейтр = "; ".join(f"N{V:g} → {L(5.0, V, 1e-6)[0]:.1f}" for V in (1, 2, 3, 4, 5, 6, 7, 8, 9, 9.5))
    тони = "; ".join(f"{н} → h {L(H, 6, 6)[2]:.1f}° (C* {L(H, 6, 6)[1]:.1f})" for н, H in
                     (("5R", 5), ("5YR", 15), ("5Y", 25), ("5GY", 35), ("5G", 45), ("5BG", 55), ("5B", 65),
                      ("5PB", 75), ("5P", 85), ("5RP", 95)))
    хрома = "; ".join(f"Манселл C{C} → C* {L(15, 6, C)[1]:.1f}" for C in (2, 4, 8, 12))
    return ("Опорні точки шкал (пораховано кодом із таблиці renotation Манселла, D65; для калібрування, не для "
            "вибору):\n"
            f"- нейтральні, L*: {нейтр}; ідеальний білий — 100.\n"
            f"- тон (основні тони Манселла на V6/C6): {тони}.\n"
            f"- хрома (5YR, V6): {хрома}.")


def запит(варіант, набір):
    """Повний текст запиту одного перекладача."""
    осі = {"А": ОСІ_А + "\n" + ІНТЕРВАЛ, "В": ОСІ_В.format(опори=опори()) + "\n" + ІНТЕРВАЛ,
           "Б": ОСІ_Б.format(словник=словник())}[варіант]
    перелік = "\n".join(f"{н}. {назва}" for н, назва in назви(набір))
    return f"{ШАПКА}\n{осі}\nНазви:\n{перелік}\n"


def main():
    for набір in НАБОРИ:
        for варіант in ВАРІАНТИ:
            (ТЕКА / f"запит_{варіант}_{набір}.txt").write_text(запит(варіант, набір), encoding="utf-8")
        (ТЕКА / f"запит_мотив_{набір}.txt").write_text(запит_мотиву(набір), encoding="utf-8")
    print("запитів:", len(НАБОРИ) * (len(ВАРІАНТИ) + 1))


if __name__ == "__main__":
    main()
