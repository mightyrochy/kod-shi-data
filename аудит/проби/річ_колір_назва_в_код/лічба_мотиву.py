"""Крок 5 «Візерунок»: чи лягає мотив із назви відтінку в клас продукту (`verify.клас_мотиву`).

Перекладач (свіжий субагент, `запит_мотив_<набір>.txt`) бачив лише 40 назв і опис запису: вид мотиву своїми
словами, розмір, напрям смуг, основа, мотив і окремим полем фактура; переліку класів продукту він не бачив. Код
лише лічить: вид перекладача → `verify.клас_мотиву` (той самий шлях, яким продукт читає слово), і для порівняння
— та сама функція прямо на назві, без перекладача. Переліку продукту проба не міняє.

Речі — ті, на яких сторінка огляду показала кольори принту моделі й власник дав вердикт «принт» (sproba2 — 12,
sproba1 — 10); мірка — вердикт власника з `лічба_<набір>_власник.tsv`. Вердикт сторінки стосувався кольорів
принту моделі (`ohliad-koloru/sets/<набір>.json`, `модель.принт`), а назву з видом мотиву власник оцінював полем
«назва»; причина «н»/«з» тут — лише факти з даних, без суду.

Рядок має й річ без вердикту, коли перекладач дав візерунок чи фактуру з класом продукту. Покриття: вид без класу, у якого перші 4 літери слова збігаються з початком кореня класу (`квіти` → `квітк`),
— «бракує форми кореня наявного класу»; інакше — «нового виду». Запуск з кореня репозиторію:

    python аудит/проби/річ_колір_назва_в_код/лічба_мотиву.py

Пише `лічба_мотиву.tsv` і друкує підсумок; вивід детермінований.
"""
import csv
import json
from pathlib import Path
import re
import sys

ТЕКА = Path(__file__).resolve().parent
КОРІНЬ = ТЕКА.parents[2]
ОГЛЯД = КОРІНЬ / "аудит/проби/річ_колір_огляд_людьми"
sys.path.insert(0, str(КОРІНЬ / "джерела"))
import verify as V  # noqa: E402

НАБОРИ = ("sproba2", "sproba1")
ЗАГАЛЬНІ = ("принт", "однотонний")


def клас(текст):
    return V.клас_мотиву(текст or "")["клас"]


def сорт(к):
    """Куди лягає слово: конкретний клас / лише «принт» / нема класу."""
    return "нема класу" if к is None else ("лише принт" if к in ЗАГАЛЬНІ else "клас")


def слова(текст):
    return re.findall(r"[а-щьюяєіїґ']+", (текст or "").lower())


def форма_кореня(вид):
    """Клас, до кореня якого слово виду близьке першими 4 літерами (лише для виду без класу)."""
    for с in слова(вид):
        if len(с) < 4:
            continue
        for корінь, кл in sorted(V.КЛАСИ_МОТИВУ.items()):
            if кл not in ЗАГАЛЬНІ and корінь[:4] == с[:4]:
                return кл, с
    return None, None


def речі(набір):
    with open(ОГЛЯД / f"лічба_{набір}_власник.tsv", encoding="utf-8") as ф:
        власник = {int(р["номер"]): р for р in csv.DictReader(ф, delimiter="\t")}
    з_набору = {р["номер"]: р for р in
                json.loads((КОРІНЬ / f"ohliad-koloru/sets/{набір}.json").read_text(encoding="utf-8"))["речі"]}
    перекл = {р["номер"]: р for р in
              json.loads((ТЕКА / f"відповідь_мотив_{набір}.json").read_text(encoding="utf-8"))["речі"]}
    if sorted(перекл) != list(range(1, 41)):
        raise ValueError(f"{набір}: перекладач дав не 40 речей")
    рядки = []
    for н in range(1, 41):
        р, с, п = власник[н], з_набору[н], перекл[н]
        принт_моделі = с["модель"].get("принт") or []
        вз = п.get("візерунок") or {}
        вердикт = {"п": "правильно", "н": "неправильно"}.get(р["принт_більшість"],
                                                               "не можу сказати" if р["принт_п/н/з"] != "0/0/0"
                                                               else "")
        if not принт_моделі and not вз and not клас(п.get("фактура")):
            continue
        вид = вз.get("вид")
        кв = клас(вид) if вид else None
        форма = форма_кореня(вид) if вид and кв is None else (None, None)
        назва = с["модель"]["назва"]
        збіг = lambda к, т: any(а[:4] == б[:4] for а in слова(к) for б in слова(т))
        де = [f"{к}: " + ("мотив" if збіг(к, вз.get("мотив")) else "основа" if збіг(к, вз.get("основа"))
                          else "у назві" if збіг(к, назва) else "поза назвою") for к in принт_моделі]
        рядки.append(dict(
            набір=набір, номер=н, назва=назва, тип=с["тип"], принт_моделі=", ".join(принт_моделі),
            вердикт_принт=вердикт, вердикт_назва=р["назва_більшість"],
            вид=вид or "", розмір=вз.get("розмір") or "", напрям=вз.get("напрям") or "",
            основа=вз.get("основа") or "", мотив=вз.get("мотив") or "", фактура=п.get("фактура") or "",
            клас_виду=кв or "", куди_вид=сорт(кв) if вид else "перекладач: візерунку нема",
            клас_назви=клас(назва) or "", куди_назва=сорт(клас(назва)),
            клас_фактури=клас(п.get("фактура")) or "", клас_типу=клас(с["тип"]) or "",
            бракує=(f"форми кореня «{форма[1]}» класу {форма[0]}" if форма[0] else
                    (f"нового виду «{вид}»" if вид and сорт(кв) != "клас" else "")),
            кольори_принту_в_записі="; ".join(де)))
    return рядки


def лічба(рядки):
    суд = [р for р in рядки if р["вердикт_принт"]]
    k = lambda ряд, поле, зн: sum(р[поле] == зн for р in ряд)
    return dict(
        речей=len(суд),
        вердикт={в: k(суд, "вердикт_принт", в) for в in ("правильно", "неправильно", "не можу сказати")},
        вид={в: k(суд, "куди_вид", в) for в in ("клас", "лише принт", "нема класу", "перекладач: візерунку нема")},
        вид_визнані={в: sum(р["куди_вид"] == в for р in суд if р["вердикт_принт"] == "правильно")
                     for в in ("клас", "лише принт", "нема класу", "перекладач: візерунку нема")},
        назва={в: k(суд, "куди_назва", в) for в in ("клас", "лише принт", "нема класу")},
        поза_вердиктом=[р["номер"] for р in рядки if not р["вердикт_принт"]],
    )


def main():
    усі = [р for н in НАБОРИ for р in речі(н)]
    поля = list(усі[0])
    with open(ТЕКА / "лічба_мотиву.tsv", "w", encoding="utf-8", newline="") as ф:
        п = csv.DictWriter(ф, fieldnames=поля, delimiter="\t", lineterminator="\n")
        п.writeheader()
        п.writerows(усі)
    for н in НАБОРИ:
        ряд = [р for р in усі if р["набір"] == н]
        print(н, json.dumps(лічба(ряд), ensure_ascii=False))
        for р in ряд:
            print(f"  {р['номер']:>2} {р['вердикт_принт'][:6]:6} вид={р['вид']!r}→{р['клас_виду'] or '—'} "
                  f"({р['куди_вид']}); назва→{р['клас_назви'] or '—'}; фактура={р['фактура']!r}→"
                  f"{р['клас_фактури'] or '—'}; тип→{р['клас_типу'] or '—'}; {р['бракує']}"
                  + f"; кольори принту: {р['кольори_принту_в_записі']}; назва: {р['вердикт_назва']}")
    бракує = {}
    for р in усі:
        if р["бракує"]:
            бракує[р["бракує"]] = бракує.get(р["бракує"], 0) + 1
    print("покриття:", json.dumps(dict(sorted(бракує.items())), ensure_ascii=False))


if __name__ == "__main__":
    main()
