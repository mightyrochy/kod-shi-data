def ранг(xs):
    порядок = sorted(range(len(xs)), key=lambda i: xs[i])
    р = [0.0] * len(xs)
    for k, i in enumerate(порядок):
        р[i] = float(k)
    return р


def спірмен(a, b):
    ra, rb = ранг(a), ранг(b)
    ma, mb = statistics.mean(ra), statistics.mean(rb)
    чис = sum((x - ma) * (y - mb) for x, y in zip(ra, rb))
    return чис / math.sqrt(sum((x - ma) ** 2 for x in ra) * sum((y - mb) ** 2 for y in rb))


