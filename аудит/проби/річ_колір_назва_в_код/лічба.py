# ─── еталон: свотчі власника ───
def прочитати_tsv(шлях):
    with open(шлях, encoding="utf-8") as ф:
        return list(csv.DictReader(ф, delimiter="\t"))


def свотчі(набір):
    """{номер: [hex, …]} — підібрані власником середини, інакше визнаний ним свотч коду (ПІСЛЯ, тоді ДО)."""
    ключ = json.loads((ОГЛЯД / f"ключ_{набір}.json").read_text(encoding="utf-8"))["речі"]
    результат = {}
    for р in прочитати_tsv(ОГЛЯД / f"лічба_{набір}_власник.tsv"):
        н = int(р["номер"])
        if н > 40:
            continue
        перший = р["середина_1_hex_OKLab"].split(" | ")[0]
        другий = р["середина_2_hex_OKLab"].split(" | ")[0]
        if not перший:
            for стан in ("ПІСЛЯ", "ДО"):
                if р[f"{стан}_більшість"] == "п":
                    перший = ключ[str(н)][стан]["hex"]
                    break
        if перший:
            результат[н] = [перший] + ([другий] if другий else [])
    return результат


