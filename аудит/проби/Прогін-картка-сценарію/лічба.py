"""Лічба мірила наряду Прогін-картка-сценарію з виводу `картка.js` (один JSON на дерево коду).

Рядок картки без джерела — рядок, у якому стоїть підпис причини ошатності (пункт правила драбини, яким мовна модель
поставила щабель: «· норма місця чи людей», «· +1, вона представляє»…): у картці запиту (`картка_запиту`) цих
проходів решта полів картки — нагода, місце, смуга погоди, пора, опади — стоїть на уривку її слів, а щабель —
читання мовною моделлю названої нею нагоди. Підписи — таблиця `причини_ошатності` довідника до правки.
Ще дві відповіді «так/ні»: чи є в аркуші «Нагода» плитка весілля, коли нагода — весілля, і чи сховано поле
«Реагенти на дорогах» поза морозом.  Запуск: python3 лічба.py до.json після.json [переп.json]"""
import json, sys
ПРИЧИНИ = ("письмова вимога", "норма місця чи людей", "+1, її оцінюють", "+1, вона представляє", "її слова")
МОРОЗ = ("frost", "deep_frost")
for шлях in sys.argv[1:]:
    проходи = json.load(open(шлях, encoding="utf-8"))
    без_джерела = [(п["сцена"], п["прохід"], н + ": " + з) for п in проходи for н, з in п["картка"]
                   if any(" · " + р in з for р in ПРИЧИНИ)]
    весілля = [п for п in проходи if п["нагода_поле"] == "весілля_гість"]
    плитка = [any("Весілля" in т and "✓" in т for т in (п["плитки"] or [])) for п in весілля]
    поза_морозом = [п for п in проходи if п["смуга"] not in МОРОЗ]
    print("%s: проходів %d · рядків картки без джерела %d · плитка весілля обрана %d з %d · реагенти сховано поза "
          "морозом %d з %d · помилок сторінки %d" % (шлях, len(проходи), len(без_джерела), sum(плитка), len(весілля),
          sum(п["реагенти_сховано"] for п in поза_морозом), len(поза_морозом), sum(len(п["помилки"]) for п in проходи)))
    for р in без_джерела:
        print("   ", *р)
