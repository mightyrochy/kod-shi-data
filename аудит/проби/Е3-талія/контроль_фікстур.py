"""Друкує наявність фікстур у всьому каталозі читачами заданої версії коду.

Запуск: python -X utf8 аудит/проби/Е3-талія/контроль_фікстур.py <тека джерела>.
Каталог має бути той самий для бази й голови; скрипт не складає образів.
"""
from pathlib import Path
import sys, json, collections
джерела = Path(sys.argv[1]).resolve()
sys.path.insert(0, str(джерела))
import feed as Ф


def вимір():
    """Міряє всі офери, не вибірку пулу; не домислює пропущених атрибутів."""
    офери, _ = Ф.читати_yml(Ф.каталог_на_диску('каталог_повний.xml', тека=str(джерела)))
    ланцюги, ремонт = [], []
    for о in офери:
        р = Ф.побудувати_запис_речі(о)
        о['запис_речі'] = р
        д = Ф.аксесуарні_довжини(о, р['слот'], р['тип'])
        if д.get('ланцюг_см') is not None:
            ланцюги.append(д['ланцюг_см'])
        if р['слот'] == 'взуття' and Ф._взуттєві_поля(о, р['тип']).get('ремонтопридатна') is False:
            ремонт.append(о['id'])
    return dict(оферів=len(офери), ланцюгів=len(ланцюги), рівно_41=ланцюги.count(41.0),
                довжини=dict(collections.Counter(ланцюги)), ремонтопридатна_false=len(ремонт))


if __name__ == '__main__':
    print(json.dumps(вимір(), ensure_ascii=False))
