T = ПС.тіло(168.0, dict(плечі=98, груди=92, талія=74, стегна=99, високе_стегно=88))
ДОВЖИНИ = {"верх": (140, 95), "низ": (100, 5), "сукня": (140, 55), "верхній_шар": (145, 60),
           "шарф": (145, 120), "сумка": (105, 95), "взуття": (12, 0)}


def з_геометрії(речі):
    """Речам — площа й near з кроку обчислення (`areas.образ_з_геометрії`), як `проба_правила`."""
    гео = {г["id"]: г for г in areas.образ_з_геометрії(T["профіль"], [
        dict(id=r["id"], верх_см=ДОВЖИНИ[r["слот"]][0], низ_см=ДОВЖИНИ[r["слот"]][1]) for r in речі])}
    return [dict(r, площа=гео[r["id"]]["площа"], near=гео[r["id"]]["near"], джерело_площі="геометрія")
            for r in речі]


print("\n2a. K-ACC-13: два металеві предмети («золото») × слот × near (виміряний / умовність слота)")
акс = collections.Counter()
NEAR = (0.05, 0.2, 0.35, 0.6, None)
СЛОТИ_А = ("прикраси", "годинник", "сумка", "шарф")
for (с1, n1), (с2, n2) in itertools.combinations_with_replacement(list(itertools.product(СЛОТИ_А, NEAR)), 2):
    E = [dict(річ=f"a-{с1}", слот=с1, метал="золото", near=(n1 if n1 is not None else _слотова_near(с1)),
              near_виміряний=n1 is not None, площа=0.02),
         dict(річ=f"b-{с2}", слот=с2, метал="золото", near=(n2 if n2 is not None else _слотова_near(с2)),
              near_виміряний=n2 is not None, площа=0.02)]
    зн = [z for z in АС.віднімання(E) if z["правило"] == "K-ACC-13"]
    акс[(зн[0]["сила"] if зн else "нема")] += 1
print("   ", dict(sorted(акс.items())), f"із {sum(акс.values())} пар")

print("\n2b. сегментація: волосся кольору речі; near з геометрії (виміряний) і без (умовність слота)")
сег = collections.Counter()
ВОЛОССЯ = "#1a1a1a"
for слоти in (("верх", "низ"), ("сукня", "взуття"), ("верхній_шар", "низ"), ("шарф", "верх", "низ"),
              ("верх", "низ", "сумка")):
    for виміряний in (True, False):
        речі = [dict(id=с, слот=с, hex=ВОЛОССЯ) for с in слоти]
        речі = з_геометрії(речі) if виміряний else [dict(r, площа=1.0 / len(речі)) for r in речі]
        E = O.елементи(речі)
        F = cs.features(cs.hx("#e0b89a"), cs.hx(ВОЛОССЯ), cs.hx("#5a4030"))
        for z in СО.перевірка_сегментації(F, E):
            сег[("виміряний" if виміряний else "умовність", z["речі"][1], z["сила"])] += 1
for к, n in sorted(сег.items()): print(f"   {n:3d}  {к}")

