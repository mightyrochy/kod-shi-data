/* Рядок 4108: температура й сід у тілі запиту стенда до моделі. Показ шле мовному шару `temperature: 0`
   (М-2: однакова репліка → один паспорт), а сіда не шле — тож сід стенда до MODEL_MOVA не доходив і
   «3 сіди» К7 були однією вибіркою. Тепер: сід стенда йде в запит мовної моделі (якщо сторінка свого не
   поклала); MODEL_TEMP — свідомий дослід для всіх викликів; MODEL_TEMP_MOVA — лише для мовної моделі
   (на 0 сіди дають однаковий текст, тож для різних вибірок ставлять, напр., 0.7). Стилістка (`MODEL`) — як було. */
const число = х => х !== null && х !== undefined && !Number.isNaN(х);
module.exports = function вибірка(тіло, мовний, {сід, темп, темпМови}){
  const о = {};
  if (число(темп)) о.temperature = темп;
  else if (мовний && число(темпМови)) о.temperature = темпМови;
  else if (typeof тіло.temperature === 'number') о.temperature = тіло.temperature;
  if (typeof тіло.seed === 'number') о.seed = тіло.seed;
  else if (мовний && число(сід)) о.seed = сід;
  return о;
};
