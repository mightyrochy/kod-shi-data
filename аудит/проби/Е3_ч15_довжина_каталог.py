# -*- coding: utf-8 -*-
"""Е3-одна-величина ч15 (п.6, довжина верхнього одягу): вердикти правил довжини ДО → ПІСЛЯ на каталозі.

Запуск із кореня репозиторію:
    python3 аудит/проби/Е3_ч15_довжина_каталог.py                       # ПІСЛЯ: код цієї гілки
    git worktree add /tmp/до <SHA_ДО>
    python3 аудит/проби/Е3_ч15_довжина_каталог.py --код /tmp/до/джерела  # ДО: той самий скрипт на старому коді

Каталог — `джерела/каталог_повний.xml` цього клону через `bridge.виклик("запити")` стенда (модель і платні API
не викликаються). Тіла — стенд і три зрости (155, 165, 175 см). Річ — `composer.у_річ` на кожному тілі.
Друкує:
  K-OUT-03/K-OUT-43 (`верхнє_довжина.краї`) — пари «верхній шар × сукня/спідниця», лічба (правило, сила, заява);
    пари зведено за підписом краю (усе, що `краї` читає), лічба — з кратністю, тобто як на повному добутку;
  K-OUT-04 — трійки «верхній шар × верх × сукня» (вибірка `random.seed(15)`, 4000 на тіло);
  K-OUT-02 — суд (`верхнє_довжина.довжина`) і пул (`нижче_коліна` на записі каталогу) на кожному верхньому шарі."""
import sys, pathlib, json, collections, os, io, contextlib, random

КОРІНЬ = pathlib.Path(__file__).resolve().parents[2]
код = pathlib.Path(sys.argv[sys.argv.index("--код") + 1]).resolve() if "--код" in sys.argv else КОРІНЬ / "джерела"
os.chdir(код); sys.path.insert(0, str(код))
import feed as Ф, bridge as B, composer as КМ, fit as ПС, верхнє_довжина as ВД

вх = json.load(open(код / "стенд_вх.json", encoding="utf-8"))
вх["каталог"] = Ф.каталог_на_диску(str(КОРІНЬ / "джерела" / "каталог_повний.xml")); вх["гілка"] = 0
with contextlib.redirect_stdout(io.StringIO()):
    json.loads(B.виклик("запити", json.dumps(вх, ensure_ascii=False)))
кат = B.каталог_останнього_пакета()
F, T_стенд, _зр, _kw = B._збірка(вх)
ТІЛА = [("стенд", T_стенд)] + [("%d см" % зр, ПС.тіло(зр, dict(плечі=обх[0], груди=обх[1], талія=обх[2], стегна=обх[3])))
                              for зр, обх in ((155, (96, 90, 72, 98)), (165, (100, 94, 76, 102)), (175, (104, 98, 80, 106)))]
слоти = collections.Counter(c.get("слот") for c in кат)
верхні = [c for c in кат if c.get("слот") == "верхній_шар"]
під = [c for c in кат if c.get("слот") in ("сукня", "низ") and (c.get("слот") == "сукня" or c.get("довжина_рівень")
                                                                 or c.get("довжина_виробу_см"))]
верхи = [c for c in кат if c.get("слот") == "верх"]
print("код: %s · верхніх %d, під ними %d, верхів %d" % (код, len(верхні), len(під), len(верхи)))
ПОЛЯ = ("довжина_рівень", "довжина_джерело", "низ_см", "край_джерело", "край_розкид_см", "край_точка_виміру",
        "довжина_виробу_см", "довжина_виробу_точка", "довжина_виробу_розкид_см", "стан", "ховає_повністю", "слот")
підпис = lambda р: tuple(str(р.get(к)) for к in ПОЛЯ)


def коди(з):
    return ",".join(sorted({x.get("code") for x in (з.get("заяви") or []) if isinstance(x, dict)})) or "—"


for ім, T in ТІЛА:
    вр = collections.Counter(); пр = collections.Counter(); зразок_в, зразок_п = {}, {}
    for c in верхні:
        р = КМ.у_річ(dict(c), "верхній_шар", T); к = підпис(р); вр[к] += 1; зразок_в.setdefault(к, р)
    for c in під:
        р = КМ.у_річ(dict(c), c["слот"], T); к = підпис(р); пр[к] += 1; зразок_п.setdefault(к, р)
    лік = collections.Counter(); пар = 0
    for кв, nв in вр.items():
        for кп, nп in пр.items():
            пар += nв * nп
            for з in ВД.краї([зразок_в[кв], зразок_п[кп]], T):
                лік[(з["правило"], з["сила"], коди(з))] += nв * nп
    print("\n== тіло %s (зріст %s) · пар %d (підписів %d × %d)" % (ім, T.get("зріст"), пар, len(вр), len(пр)))
    for (п, с, к), n in sorted(лік.items()):
        print("   %-9s %-9s %-45s %9d" % (п, с, к, n))
    random.seed(15); к04 = collections.Counter()
    for _ in range(4000):
        речі = [КМ.у_річ(dict(random.choice(верхні)), "верхній_шар", T), КМ.у_річ(dict(random.choice(верхи)), "верх", T),
                КМ.у_річ(dict(random.choice([c for c in під if c["слот"] == "сукня"])), "сукня", T)]
        for з in ВД.краї(речі, T):
            к04[(з["правило"], з["сила"])] += 1
    print("   трійки (4000): " + ", ".join("%s %s %d" % (п, с, n) for (п, с), n in sorted(к04.items())))
    суд02 = collections.Counter(); пул = collections.Counter()
    for c in верхні:
        р = КМ.у_річ(dict(c), "верхній_шар", T)
        суд02["K-OUT-02" if any(з["правило"] == "K-OUT-02" for з in ВД.довжина([р], T)) else "—"] += 1
        пул[ВД.нижче_коліна(c, T.get("висоти"))] += 1
    print("   K-OUT-02 суд: %s" % dict(суд02))
    print("   нижче_коліна (пул): %s" % dict(sorted(пул.items(), key=str)))
