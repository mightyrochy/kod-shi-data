"""РЕМОНТ-2 (рядки 4291, 4352, 4490, 4491): записані відповіді ремонту заміру РЕМОНТ-1 — крізь міст робочої копії, без
моделі. Промпт ремонту будує чинний код (довжина, правила, «done» у схемі, «gates», «bold»), а та сама записана відповідь
іде мостом ітерації 2 (`аудит/проби/гг1_повтор_ремонту.py`, `бік`): скільки образів після, ід образу відповіді, сміливі
нового суду. Порівняння — текст відповідей кожного боку і повтор кожного боку його копією коду (офлайн обидва боки —
ті самі записи; живий ПІСЛЯ — нові записи `гг1_повтор_ремонту.py`, повторені кодом PR).
  cd <копія>/джерела && python3 ../аудит/проби/ремонт2_повтор_записів.py <тека з сирі/> <вихід.json>
  python3 аудит/проби/ремонт2_повтор_записів.py --порівняти <тека ДО> <до.json> <тека ПІСЛЯ> <після.json>"""
import gzip, json, glob, os, re, sys, collections as K

ДАНІ = re.compile(r'"(fixes|not_run_everywhere|set|showcase|verdict|case|break_kind|language|register|outfits_wanted|'
                  r'input|statement_codes|answer_schema)"\s*:')     # дані промпту в тексті відповіді; «day» — поле образу
DONE = re.compile(r'\{\s*"finding"\s*:\s*"([^"]+)"\s*,\s*"action"\s*:\s*"[^"]*"(?:\s*,\s*"why"\s*:\s*"(?:[^"\\]|\\.)*")?\s*\}')
лат = lambda і: str(і or "").replace("о", "o")


def записи(тека):
    for ф in sorted(glob.glob(os.path.join(тека, "сирі", "*.json.gz"))):
        з = json.load(gzip.open(ф, "rt", encoding="utf-8"))
        if not (з.get("з_гг1") or {}).get("збій") and (з.get("з_гг1") or {}).get("виклики"):
            yield з["ключ"], з["з_гг1"]


def повтор(тека, вихід):
    sys.path.insert(0, "."); sys.path.insert(0, "../аудит/проби"); os.environ["BOKY"] = "з_гг1"
    import гг1_повтор_ремонту as Г
    входи = {json.loads(л)["ключ"]: json.loads(л) for л in gzip.open(Г.ВХОДИ, "rt", encoding="utf-8")}
    міст, ост, вих = Г.міст, {}, {}

    def стежити(ім, вх):
        р = міст(ім, вх)
        if ім == "від_моделі":
            ост["р2" if вх.get("ітерація") == 2 else "р1"] = р
        return р
    Г.міст = стежити
    for к, х in записи(тека):
        ост.clear(); т = iter([(в["статус"], в["текст"], в["обрізано"], в["с"]) for в in х["виклики"]])
        р = Г.бік(входи[к]["вх"], входи[к]["текст"], True, lambda п, о=None: next(т, (599, "", False, 0)))
        п = json.loads(р.pop("промпт", "") or "{}"); р2 = ост.get("р2") or {}; з = п.get("task") or {}
        вих[к] = dict(збій=р.get("збій"), ід_моделі=р.get("ід_моделі"), обрано=р.get("обрано"),
                      промпт=dict(символів=len(json.dumps(п, ensure_ascii=False, separators=(",", ":"))), правил=len(з.get("rules") or []),
                                  done_у_схемі='"done"' in json.dumps(з.get("answer_schema") or {}),
                                  gates=sum(len(о.get("gates") or []) for о in п.get("verdict") or []), bold=(п.get("set") or {}).get("bold")),
                      образи_р2=[dict(номер=о.get("номер"), ід_відповіді=о.get("ід_відповіді"), блокує=bool(о.get("блокує")))
                                 for о in р2.get("образи") or []],
                      сміливі_після=((р2.get("вердикт") or {}).get("набір") or {}).get("сміливі"))
        print(к, len(вих[к]["образи_р2"]), [о["ід_відповіді"] or о["номер"] for о in вих[к]["образи_р2"]], flush=True)
    json.dump(вих, open(вихід, "w", encoding="utf-8"), ensure_ascii=False)


def порівняти(тека_до, до, тека_після, після):
    Р = {"ДО": K.Counter(), "ПІСЛЯ": K.Counter()}
    for бік, тека, ф in (("ДО", тека_до, до), ("ПІСЛЯ", тека_після, після)):
        Л, спільні = Р[бік], set(json.load(open(до, encoding="utf-8"))) & set(json.load(open(після, encoding="utf-8")))
        for к, х in записи(тека):
            if к not in спільні:
                continue
            гейти = {z["id"] for о in json.loads(х["промпт"])["verdict"] for z in о.get("findings") or [] if z.get("register") == "gate"}
            for в in х["виклики"]:
                т = в["текст"]; Л["викликів"] += 1; Л["обрізано"] += в["обрізано"]; Л["з даними промпту в тексті"] += bool(ДАНІ.search(т))
                Л["символів відповідей"] += len(т)
                for м in DONE.finditer(т):
                    Л["done над гейтом" if м.group(1) in гейти else "done над зауваженням"] += 1
        for к, р in json.load(open(ф, encoding="utf-8")).items():
            if к not in спільні:
                continue
            п, о2 = р["промпт"], р["образи_р2"]; b = п.get("bold") or {}
            Л["пар"] += 1; Л["символів промпту"] += п["символів"]; Л["правил"] += п["правил"]; Л["done у схемі"] += п["done_у_схемі"]
            Л["gates на дроті"] += п["gates"]; Л["образів після"] += len(о2); Л["пар з образів після < 5"] += len(о2) < 5
            Л["образів з ід відповіді"] += sum(bool(о["ід_відповіді"]) for о in о2)
            Л["ід образу = номер"] += sum(лат(о["ід_відповіді"] or о["номер"]) == лат(о["номер"]) for о in о2)
            Л["образи = «chosen» (за ід)"] += bool(р.get("обрано")) and [лат(о["ід_відповіді"]) for о in о2] == [лат(і) for і in р["обрано"]][:len(о2)]
            if b:
                взято = {лат(о["ід_відповіді"] or о["номер"]) for о in о2}
                смл = {лат(x["id"]) for x in b.get("outfits") or []}; нв = {лат(і) for і in b.get("not_measured") or []}
                Л["пар із set.bold"] += 1; Л["доза порушена (сміливі за ід)"] += len(взято & смл) < b["keep_at_least"]
                Л["доза не встановлена (і невиміряні)"] += len(взято & (смл | нв)) < b["keep_at_least"]
                Л["невиміряних у set.bold"] += len(нв)
                Л["сміливих серед повернутих (новий суд)"] += len((р.get("сміливі_після") or {}).get("образи") or [])
    for к in Р["ПІСЛЯ"]:
        print("  %-40s ДО %-7s ПІСЛЯ %s" % (к, Р["ДО"][к], Р["ПІСЛЯ"][к]))


if __name__ == "__main__":
    порівняти(*sys.argv[2:6]) if sys.argv[1] == "--порівняти" else повтор(sys.argv[1], sys.argv[2])
