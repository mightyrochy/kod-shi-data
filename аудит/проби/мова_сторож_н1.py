"""Наряд Н-1, частина 2 (М-1, PR #363 «Що міряти наживо»): скільки полів перекладача стоять на
цитаті, скільки з них відкинув сторож `_тримається` і скільки з відкинутих — СПРАВЖНІ поля, що
загинули лише через недослівну цитату (відмінок, порядок слів). Плюс `question_about` (app|look).

Проба кличе рівно те, що кличе продукт: `мовний_шар.промпт_входу("scenario", слова)` → модель →
`прийняти_вхід` → `_тримається`. «▁» (SentencePiece Lapa) знімається так само, як у
`каталог_розбір.з_відповіді` — до розбору, щоб вимір мірив зміст, а не токенізатор.

«Справжнє поле, відкинуте лише через недослівність» рахується механічно, без ока: цитата
непорожня І всі її слова (нормалізовані `_до_звірки`) з довжиною ≥ 4 знайшлись у словах жінки
початком слова — тобто модель процитувала майже дослівно, а сторож вимагає підрядка.

Запуск (з теки джерела):
  MODEL_URL=http://127.0.0.1:1234/v1 MODELS=м1,м2 python ../аудит/проби/мова_сторож_н1.py <тека>
"""
