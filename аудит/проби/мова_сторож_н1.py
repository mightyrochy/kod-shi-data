sys.path.insert(0, os.getcwd())
sys.stdout.reconfigure(encoding="utf-8")
import мовний_шар as МШ                                                        # noqa: E402

# 10 фраз П.6 з #304 (`аудит/проби/мова_вхід.py`) + фраза власника 25.09 (В-1 наряду М-1).
ФРАЗИ = ["гуляю з собаками в парку, вітер, яскраво хочу одягатись, по-дівчачому, ніжний і зручний "
         "образ у світлих тонах, у мене є світлі джинси кльош",
         "робочий день в офісі, дрес-код business casual, без підборів", "смужку? ні, клітинку хочу",
         "хочу смужку", "люблю смужку. ні", "не хочу темні", "ні в якому разі",
         "куртку чи жакет, не темного кольору", "не ношу куртки, краще пальто чи тренч",
         "не хочу привертати уваги",
         "Збери образ під цю спідницю і чоботи для походу на концерт"]
# 6 питань: три про застосунок (app), три про образ (look) — маршрут 8/8 наряду М-1.
ПИТАННЯ = [("Де тут зберігаються мої образи?", "app"),
           ("Як видалити профіль із застосунку?", "app"),
           ("Чому кнопка «Зібрати образи» не натискається?", "app"),
           ("Чи пасує ця спідниця до моїх чобіт?", "look"),
           ("Що мені вдягнути зверху до цієї сукні?", "look"),
           ("Цей колір мені личить?", "look")]
ВСТАВКА = "▁"   # той самий підхід, що `каталог_розбір.ВСТАВКА`


def дзвінок(модель, промпт):
    тіло = dict(model=модель, max_tokens=2000, stream=False, reasoning_effort="none",
                messages=[dict(role="user", content=промпт)],
                **({"temperature": float(os.environ["TEMPERATURA"])} if os.environ.get("TEMPERATURA") else {}))
    зап = urllib.request.Request(os.environ.get("MODEL_URL", "http://127.0.0.1:1234/v1").rstrip("/")
                                 + "/chat/completions", json.dumps(тіло).encode("utf-8"),
                                 {"Content-Type": "application/json"})
    т0 = time.time()
    відп = json.load(urllib.request.urlopen(зап, timeout=1800))["choices"][0]["message"].get("content") or ""
    return відп.replace(ВСТАВКА, ""), time.time() - т0


def майже(цитата, слова):
    """Чи процитувала модель майже дослівно: кожне слово цитати довжиною ≥ 4 стоїть у її словах
    початком якогось слова (відмінок і порядок слів не важать). Без словників і лем."""
    ц, т = МШ._до_звірки(цитата), МШ._до_звірки(слова)
    слова_ц = [с for с in ц.split() if len(с) >= 4]
    if not слова_ц:
        return False
    основи = [с[:max(4, len(с) - 2)] for с in слова_ц]
    return all(re.search(r"(^| )" + re.escape(о), т) for о in основи)


def цитата_поля(поле, значення, цитати):
    """Цитата, на якій стоїть поле — так само, як її бере `_тримається`."""
    if поле in МШ._РЕЧІ_З_ЦИТАТОЮ and isinstance(значення, list):
        return [(р.get("quote") or ((р.get("name") or {}).get("free_text")
                if поле == "own_items" else None) or цитати.get(поле)) for р in значення]
    return [цитати.get(поле)]


def main():
    тека = sys.argv[1] if len(sys.argv) > 1 else sys.exit("треба тека для сирих відповідей")
    os.makedirs(тека, exist_ok=True)
    моделі = [м for м in os.environ.get("MODELS", "").split(",") if м]
    for м in моделі:
        усього = з_цитатою = відкинуто = лише_недослівні = без_цитати = не_json = 0
        print("\n═══ %s · 11 фраз ═══" % м, flush=True)
        print("| № | фраза | полів | з цитатою | відкинув сторож | з них лише недослівні | JSON |")
        print("|---" * 7 + "|")
        for і, фраза in enumerate(ФРАЗИ, 1):
            промпт = МШ.промпт_входу("scenario", фраза)
            сире, с = дзвінок(м, промпт)
            відк = МШ.прийняти_вхід("scenario", сире)
            вн = відк["внутрішня"]
            open(os.path.join(тека, "%s__fraza%02d.txt" % (re.sub(r"[^\w.-]+", "_", м), і)), "w",
                 encoding="utf-8").write("── ПРОМПТ (%d симв.) ──\n%s\n\n── ВІДПОВІДЬ (%d симв., %.1f с) ──\n%s\n"
                                         % (len(промпт), промпт, len(сире), с, сире))
            цитати = dict(вн.get("quotes") or {})
            поля = [к for к in вн if к != "quotes"]
            _взяті, рядки = МШ._тримається(вн, фраза)
            єц = sum(1 for к in поля for ц in цитата_поля(к, вн[к], цитати) if ц)
            недосл = безц = 0
            for рядок in рядки:
                м_ц = re.search(r"· цитата: «(.*?)» — у її словах нема", рядок)
                if м_ц and майже(м_ц.group(1), фраза):
                    недосл += 1
                elif "· цитата: нема" in рядок:
                    безц += 1
            усього += len(поля); з_цитатою += єц; відкинуто += len(рядки)
            лише_недослівні += недосл; без_цитати += безц
            не_json += 1 if відк["причина"] else 0
            print("| %d | %s | %d | %d | %d | %d | %s |"
                  % (і, фраза[:44], len(поля), єц, len(рядки), недосл,
                     "НІ: " + відк["причина"][:40] if відк["причина"] else "так"), flush=True)
            for рядок in рядки:
                print("    ✗ %s" % рядок[:190])
        print("РАЗОМ %s: полів %d · з цитатою %d · відкинув сторож %d (з них: цитати не дала зовсім %d, "
              "цитата майже дослівна %d, цитата зовсім чужа %d) · відповідей не JSON %d з %d"
              % (м, усього, з_цитатою, відкинуто, без_цитати, лише_недослівні,
                 відкинуто - без_цитати - лише_недослівні, не_json, len(ФРАЗИ)))

        влучань = 0
        print("\n--- question_about (app|look), 6 питань ---")
        for і, (пит, оч) in enumerate(ПИТАННЯ, 1):
            промпт = МШ.промпт_входу("scenario", пит)
            сире, с = дзвінок(м, промпт)
            вн = МШ.прийняти_вхід("scenario", сире)["внутрішня"]
            open(os.path.join(тека, "%s__pyt%02d.txt" % (re.sub(r"[^\w.-]+", "_", м), і)), "w",
                 encoding="utf-8").write("── ПРОМПТ (%d симв.) ──\n%s\n\n── ВІДПОВІДЬ (%.1f с) ──\n%s\n"
                                         % (len(промпт), промпт, с, сире))
            є = вн.get("question_about")
            влучань += 1 if є == оч else 0
            print("| %d | %s | очікувано %s | модель %s | question: %s |"
                  % (і, пит[:44], оч, є, str(вн.get("question") or "")[:40]), flush=True)
        print("question_about влучань: %d з %d" % (влучань, len(ПИТАННЯ)))


if __name__ == "__main__":
    main()
