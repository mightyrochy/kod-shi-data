"""П.6 наряду 25.09: чистота української в тексті для людини — лічба на кожен текст і на групу.
(а) літери ы э ё ъ; (б) слова, яких нема в hunspell uk_UA (spylls; латиниця й БІЛИЙ СПИСОК жаргону не рахуються —
рішення власника: «лук», «аутфіт», «оверсайз» — жива мова, не помилка); (в) звертання на «ви» (займенник або наказ
множини). Вхід — JSONL: {"група": …, "мітка": …, "текст": …}. Словник: LibreOffice dictionaries/uk_UA (.dic + .aff).
Запуск: python аудит/проби/мова_лічильник.py <шлях_до_uk_UA без розширення> <тексти.jsonl> [--слова]"""
import json, re, sys, collections
from spylls.hunspell import Dictionary
ЖАРГОН = {"аутфіт", "аутфіти", "аутфіту", "аутфітом", "кросбоді", "шопер", "шопером", "тоут", "тоутом", "лонгслів",
          "кейп", "кроптоп", "total", "look", "тотал", "лук", "луку", "луком", "беж", "мом", "чинос", "оверсайз",
          "шоппер", "шоппером", "айворі", "бомбер", "дрес-код", "дрес-коду", "дрес-кодом"}   # останні — норма, якої нема в hunspell
РОС_ЛІТЕРИ = re.compile(r"[ыэёъЫЭЁЪ]")
ВИ = re.compile(r"(?<![\w'ʼ’-])(ви|вас|вам|вами|ваш\w*|\w{3,}(?:йте|іть|ьте))(?![\w'ʼ’-])", re.I)
НЕ_НАКАЗ = {"мідь", "сіть", "віть", "кіть", "зіть", "навіть"}
СЛОВО = re.compile(r"[А-Яа-яІіЇїЄєҐґЫыЭэЁёЪъ'ʼ’-]+")
д = Dictionary.from_files(sys.argv[1])
показ = "--слова" in sys.argv
def добре(ч, не_останнє):   # «пудрово-рожевий»: перша частина складного прикметника — основа на -о/-е від слова на -ий
    return ч.lower() in ЖАРГОН or д.lookup(ч) or д.lookup(ч.lower()) or (не_останнє and ч[-1:].lower() in "ое" and д.lookup(ч.lower()[:-1] + "ий"))
групи = collections.defaultdict(lambda: [0, 0, 0, 0, 0])   # тексти, слова, поза словником, літери ыэёъ, «ви»
поза_всього = collections.Counter()
for рядок in open(sys.argv[2], encoding="utf-8"):
    з = json.loads(рядок); т = з["текст"] or ""
    слова = [с.strip("-'ʼ’").replace("’", "'").replace("ʼ", "'") for с in СЛОВО.findall(т)]
    слова = [с for с in слова if с and not re.search(r"[A-Za-z]", с)]
    поза = [с for с in слова if с.lower() not in ЖАРГОН and not all(добре(ч, і < с.count("-")) for і, ч in enumerate(с.split("-")) if ч)]
    ви = [м.group(0) for м in ВИ.finditer(т) if м.group(0).lower() not in НЕ_НАКАЗ]
    г = групи[з["група"]]; г[0] += 1; г[1] += len(слова); г[2] += len(поза); г[3] += len(РОС_ЛІТЕРИ.findall(т)); г[4] += len(ви)
    поза_всього.update(с.lower() for с in поза)
    if показ and (поза or ви):
        print("  %s · %s · поза словником: %s · «ви»: %s" % (з["група"], з["мітка"], ", ".join(поза) or "—", ", ".join(ви) or "—"))
for н, (т_, сл, п, л, в) in групи.items():
    print("%-28s текстів %3d · слів %5d · поза словником %3d (%.1f на 1000) · ыэёъ %d · «ви» %d (%.1f на 1000)"
          % (н, т_, сл, п, 1000 * п / max(сл, 1), л, в, 1000 * в / max(сл, 1)))
print("найчастіші поза словником:", ", ".join("%s×%d" % кв for кв in поза_всього.most_common(25)))
print("білий список жаргону (не рахується):", ", ".join(sorted(ЖАРГОН)))
