def поля(знач):
    """Ключі значень заяви; категорійні (рядок, булеве) — з самим значенням: бік, тон пари, «далі від середини»."""
    return tuple(sorted(к + ("=%s" % в if isinstance(в, (str, bool)) else "") for к, в in (знач or {}).items()
                        if к != "items"))


def ключ(z):
    return (z["правило"], z["сила"], tuple(sorted((з["code"], поля(з.get("values")))
                                                  for з in (z.get("заяви") or []))))


