#!/usr/bin/env python3
"""Ціна й час проби «Живий-як-людина-1»: модель продукту (журнал_моделі_продукту.jsonl, по проходах) і сесії жінок
(службове/<с>/жінка.json). Виклики продукту перших спроб с3 і с4 (до їхнього повтору) — окремо як відкинуті.
Запуск із теки стенд/: python3 звести.py > ціна.md"""
import json, glob, os, collections
ВІДК = {"с3_дощ_замшеві_чоботи": "06:43:38", "с4_побачення_19_30": "07:03:32"}  # початок повтору, UTC
пр = collections.defaultdict(lambda: [0, 0.0, 0, 0]); відк = 0.0; відк_н = 0
for л in open("журнал_моделі_продукту.jsonl"):
    д = json.loads(л); п = д["прохід"]
    if п in ВІДК and д["початок_utc"] < ВІДК[п]:
        відк += д["usd"] or 0; відк_н += 1; continue
    з = пр[п]; з[0] += 1; з[1] += д["usd"] or 0; з[2] += д["статус"] != 200; з[3] += д.get("фото_не_дійшло") or 0
print("| ситуація | викликів продукту | не 200 | фото не дійшло до моделі | $ продукту | кроків жінки | $ жінки | разом $ |")
print("|---|---|---|---|---|---|---|---|")
сп = сж = 0.0
for п in sorted(пр):
    ж = json.load(open(f"службове/{п}/жінка.json")) if os.path.exists(f"службове/{п}/жінка.json") else {}
    з = пр[п]; сп += з[1]; сж += ж.get("usd", 0)
    print(f"| {п} | {з[0]} | {з[2]} | {з[3]} | {з[1]:.2f} | {ж.get('кроків', '—')} | {ж.get('usd', 0):.2f} | {з[1] + ж.get('usd', 0):.2f} |")
print(f"| **разом** | {sum(з[0] for з in пр.values())} | | | **{сп:.2f}** | | **{сж:.2f}** | **{сп + сж:.2f}** |")
print(f"\nВідкинуто в цьому журналі (перші спроби с3 і с4 до повтору): {відк_н} викликів, ${відк:.2f}.")
