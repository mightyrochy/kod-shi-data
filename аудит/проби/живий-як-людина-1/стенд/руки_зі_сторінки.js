/* Рука кожного образу й фото кожної картки — службове (наряд Стенд-як-людина-рука-образу, рядки 15122–15123). Беремо з самої
   сторінки, без правки продукту: `ЗБ.ключ[поз]` — рука, що дала картку `#к-<поз>` (ключ перемішано сідом входу
   `ЗБ.вхід_рук.сід`), `ЗБ.діагноз` «control · hand_2_broken=…» і `ЗБ.поломка` — назва поломки руки 2, `img` у `.ф` і
   `.річ` — що картка справді показала. Пише лише у службові файли ситуації: жінка й суддя цього не читають. */
async function знімокРук(стор){
  return стор.evaluate(() => {
    /* Показане — це `П` і картки в DOM (їх координатор міняє на шві, коли ГОТОВІ ВСІ руки), а `ЗБ` уже може належати
       наступному збиранню. Рука й прогін — з `П` (`П.розклад` — ключ саме цих карток). Сід і поломка руки 2 живуть лише в `ЗБ`:
       беруться, коли ті самі об'єкти карток стоять і в `П.картки`, і в `ЗБ.картки` (на шві `П.картки` = `ЗБ.картки.filter(Boolean)`,
       `збирання_образів.js:348`) — тотожність об'єктів, а не збіг ключа перестановки; інакше — null («невідомо»). Без `П` на
       екрані нема образів — запису нема, це не прохід. */
    if (typeof П === 'undefined' || !П || !П.розклад || !П.прогін) return null;
    const ключП = String(П.розклад), картокП = П.картки || [];
    const ЗБтой = typeof ЗБ !== 'undefined' && !!ЗБ && картокП.length > 0 && картокП.every(к => (ЗБ.картки || []).includes(к));
    const рядок = (т, н) => String(т == null ? '' : т).replace(/\s+/g, ' ').trim().slice(0, н || 120);
    const стан = і => ({src: і.getAttribute('src') || '', завантажено: !!(і.complete && і.naturalWidth > 0), w: і.naturalWidth || 0,
                        h: і.naturalHeight || 0, завершено: !!і.complete, lazy: і.loading === 'lazy'});
    const картки = Array.from(document.querySelectorAll('[id^="к-"]')).filter(е => /^к-\d+$/.test(е.id));
    const зЗБ = поз => ((ЗБтой && ЗБ.картки || [])[поз] || null);
    /* ОБРАЗ ЗНАЄ, ЗВІДКИ ВІН (наряд Екран-наново): сід, ключ і руку свого збирання показана картка несе сама — у зрізі
       образів стану екрана (`Екран.стан.образи`, коли він про цей самий прогін), а доти — у `П.картки[поз].збирання`.
       Є воно — пари `ЗБ`/`П` не питаємо; нема (збірка до наряду, картка з бібліотеки старого запису) — як було. */
    const зріз = (typeof Екран !== 'undefined' && Екран.стан.образи && Екран.стан.образи.прогін === String(П.прогін)) ? Екран.стан.образи : null;
    const збиранняПоз = поз => (зріз && (зріз.картки[поз] || {}).збирання) || (картокП[поз] || {}).збирання || null;
    const своє = картокП.map((_, поз) => збиранняПоз(поз)).filter(Boolean);
    const сідКарток = своє.length && своє.every(з => з.сід === своє[0].сід) ? своє[0].сід : null;
    const позиції = картки.map((к, н) => {
      const поз = Number(к.id.slice(2)), дані = (typeof П !== 'undefined' && П && (П.картки || [])[поз]) || зЗБ(поз) || {};
      const вих = (дані.речі || []).map(х => ({ід: х && х.id || '', фото: (х && х.фото) ? String(х.фото).slice(0, 300) : null,
                                              кадрів: ((х && х.фото_усі) || []).filter(Boolean).length}));
      const фо = Array.from(к.querySelectorAll('.ф')).map(ф => {
        const і = ф.querySelector('img'), в = вих.find(х => х.ід === (ф.dataset.id || ''));
        /* мертвий кадр замінено силуетом — адреси в DOM нема, лишається та, що в даних картки */
        return {ід: ф.dataset.id || '', ...(і ? стан(і) : {силует: true, src: '', завантажено: false, w: 0}), src_дані: в ? в.фото : null};
      });
      const речі = Array.from(к.querySelectorAll('.річ')).map(о => {
        const і = о.querySelector('img.мініатюра');
        return {назва: рядок((о.querySelector('.н') || о).innerText, 80), слот: о.dataset.слот || '',
                мініатюра: і ? стан(і) : null};
      });
      const зб = збиранняПоз(поз);
      return {позиція: н + 1, ід_картки: к.id, рука: зб ? String(зб.рука) : (ключП[поз] || null), збирання: зб, ф: фо, речі, дані_речей: вих};
    });
    const діагн = ЗБтой ? (ЗБ.діагноз || []).filter(д => /hand_2_broken|control ·/.test(д)).map(д => рядок(д, 300)) : [];
    return {сід: сідКарток != null ? сідКарток : (ЗБтой && ЗБ.вхід_рук ? ЗБ.вхід_рук.сід : null), ключ: ключП, прогін: П.прогін,
            поломка_руки_2: {діагноз: діагн, що: ЗБтой && ЗБ.поломка ? рядок(JSON.stringify(ЗБ.поломка), 400) : null,
                             контроль: ЗБтой && ЗБ.контроль ? ЗБ.контроль.поломка || null : null},
            готово: ЗБтой ? !!ЗБ.готово : true, збирання_збігається: ЗБтой, позиції};
  }).catch(е => { console.error("знімокРук:", String(е).slice(0, 200)); return null; });
}
/* Усі фото карток — зараз, не коли дійде прокрутка (`loading="lazy"`): так «не завантажилось» не плутається з «не доскролила». */
async function доЗавантажитиФото(стор){
  await стор.evaluate(() => { document.querySelectorAll('[id^="к-"] img').forEach(і => { if (і.loading === 'lazy') і.loading = 'eager'; }); }).catch(() => {});
}
module.exports = {знімокРук, доЗавантажитиФото};
