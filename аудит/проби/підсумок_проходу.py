"""Підсумок одного проходу стенда з ЙОГО Ж файлу вердиктів (наряд тестувальниці, крок 3).

Друкує рівно ті числа, які просить таблиця наряду, і бере їх із того самого файла,
який жінка вивантажує кнопкою «Зберегти всі вердикти файлом» (`ZVIT_OUT`):
рука · речей · чи є взуття і сумка · чи образ повний (≥5 речей, із сукнею ≥4) ·
скільки речей повторилось із попередніми картками · виклики й ітерації · опис.
Нічого не рахує з назв: слот кожної речі лежить у `речі_образу`.

Запуск:  python аудит/проби/підсумок_проходу.py <тека_прогону>/verdykty.txt
"""
import json
import sys

ф = sys.argv[1]
д = json.load(open(ф, encoding="utf-8"))
усі_речі, повних, карток = [], 0, 0
for прогін in д.get("прогони", []):
    for в in прогін.get("вердикти", []):
        речі = в.get("речі_образу") or []
        слоти = [р.get("слот") for р in речі]
        ід = [р.get("id") for р in речі]
        сукня = "сукня" in слоти or "комплект" in слоти
        повний = (len(речі) >= (4 if сукня else 5)
                  and "взуття" in слоти and "сумка" in слоти)
        # «м-NNN» — вигадані речі рук 3–4: у них номер той самий у кожній руці за
        # побудовою, і рахувати це як повтор означало б міряти схему нумерації
        каталожні = [i for i in ід if not str(i).startswith("м-")]
        повтор = [i for i in каталожні if i in усі_речі]
        усі_речі += каталожні
        повних += 1 if повний else 0
        карток += 1
        print("рука %s · речей %2d · взуття %s · сумка %s · повний %s · повтор із попередніх %d %s"
              % (в.get("рука"), len(речі), "так" if "взуття" in слоти else "НІ",
                 "так" if "сумка" in слоти else "НІ", "так" if повний else "НІ",
                 len(повтор), повтор or ""))
        print("   викликів %s · ітерацій %s · мова %s · опис: %s"
              % (в.get("викликів"), в.get("ітерацій"), в.get("мова") or "—",
                 (в.get("опис") or "(нема)")[:150]))
print("РАЗОМ: карток %d · повних %d · речей %d, різних %d"
      % (карток, повних, len(усі_речі), len(set(усі_речі))))
