"""Крок 26: порівняння знімків `вимір.py` бази й голови — роль нейтралі за словами крамниць, сім'я темних червоних,
`несе_колір`, збіг підпису зі словом, рід / межі / акцент, стик, сітка LCh, палітри.
Запуск із кореня: python3 аудит/перевірка/річ_колір_межі_крок26/до_після.py до.json після.json > …/до_після.txt"""
import collections, json, sys
Д, П = (json.load(open(ф, encoding="utf-8")) for ф in sys.argv[1:3])
ДЗ, ПЗ = Д["записи"], П["записи"]
assert ДЗ.keys() == ПЗ.keys(), "різні каталоги"
виміри = [к for к in ДЗ if "lch" in ДЗ[к]]
вид = lambda в: в or "колір"
print(f"записів: {Д['записів']}; з кольором: {len(ДЗ)}; з виміром: {len(виміри)}; секунд знімка {Д['секунд']} → {П['секунд']}")

def перехід(поле, ключі, прикладів=3, рядків=20):
    пер, пр = collections.Counter(), collections.defaultdict(list)
    for к in ключі:
        а, б = ДЗ[к].get(поле), ПЗ[к].get(поле)
        if а != б:
            т = f"{а} → {б}"; пер[т] += 1
            if len(пр[т]) < прикладів:
                пр[т].append(f"«{ДЗ[к]['слово']}» {ДЗ[к].get('lch', '')}")
    print(f"  {поле}: змінилось {sum(пер.values())} з {len(ключі)}")
    for т, n in пер.most_common(рядків):
        print(f"    {т}: {n} — {'; '.join(пр[т])}")
    return пер

print("\n1. Роль нейтралі (вимір, `нейтраль`) за словами крамниць")
перехід("нейтраль", виміри)
сл = collections.defaultdict(lambda: [0, 0, 0])
for к in виміри:
    с = сл[ДЗ[к]["слово"]]; с[0] += 1; с[1] += ДЗ[к]["нейтраль"] is not None; с[2] += ПЗ[к]["нейтраль"] is not None
print("  слово: вимірів, нейтраль ДО → ПІСЛЯ (слова, де змінилось, за числом вимірів)")
for w, (n, а, б) in sorted(сл.items(), key=lambda x: -x[1][0]):
    if а != б:
        print(f"    «{w}»: {n}, {а} → {б}")
for поле in ("рід", "меж", "акцент"):
    перехід(поле, list(ДЗ), рядків=8)

print("\n2. Темні червоні: вимір L* ≤ 50, h 330–30°, C* ≥ 6 — нейтраль і сім'я за словом")
темні = [к for к in виміри if ДЗ[к]["lch"][0] <= 50 and ДЗ[к]["lch"][1] >= 6 and not 30 < ДЗ[к]["lch"][2] < 330]
тс = collections.Counter((ДЗ[к]["слово"], f"{вид(ДЗ[к]['нейтраль'])}/{ДЗ[к]['сім_я']}", f"{вид(ПЗ[к]['нейтраль'])}/{ПЗ[к]['сім_я']}") for к in темні)
print(f"  вимірів {len(темні)}; (слово, ДО, ПІСЛЯ), перші 20:")
for (w, а, б), n in тс.most_common(20):
    print(f"    «{w}»: {а} → {б}: {n}")
перехід("сім_я", виміри, рядків=12)

print("\n3. `несе_колір`")
перехід("несе", list(ДЗ), прикладів=4, рядків=12)
нс = collections.Counter((ДЗ[к]["слово"], ДЗ[к]["несе"], ПЗ[к]["несе"]) for к in ДЗ if ДЗ[к]["несе"] != ПЗ[к]["несе"])
print("  за словом крамниці, перші 15:", "; ".join(f"«{w}» {а}→{б}: {n}" for (w, а, б), n in нс.most_common(15)))

print("\n4. Підпис `palettes.назва` (вимір) і слово крамниці")
збіг = [sum(З[к]["назва"] == З[к]["слово"] for к in виміри) for З in (ДЗ, ПЗ)]
print(f"  збіг зі словом {збіг[0]} → {збіг[1]}; підпис змінився в {sum(ДЗ[к]['назва'] != ПЗ[к]['назва'] for к in виміри)}")

print("\n5. Стик модуля (≥ 3 значних сімей), вимір:", sum(ДЗ[к]["стик"] for к in виміри), "→", sum(ПЗ[к]["стик"] for к in виміри))

print("\n6. Сітка LCh (L 5–95 крок 5, C 0–82 крок 2, h крок 5), `нейтраль`:")
сп = collections.Counter(f"{вид(Д['сітка'][к])} → {вид(П['сітка'][к])}" for к in Д["сітка"] if Д["сітка"][к] != П["сітка"][к])
print(f"  вузлів {len(Д['сітка'])}; змінилось {sum(сп.values())} — {сп.most_common(12)}")
for стан in (Д, П):
    н = [tuple(map(int, к.split(","))) for к, в in стан["сітка"].items() if в]
    print(f"  нейтраль: вузлів {len(н)}, найбільша C* {max(c for _, c, _ in н)}")

print("\n7. `палітра_практична` на 300 людях")
зм = [і for і, (а, б) in enumerate(zip(Д["палітри"], П["палітри"])) if а != б]
ключі = collections.Counter(к for і in зм for к in set(Д["палітри"][і]) | set(П["палітри"][і]) if Д["палітри"][і].get(к) != П["палітри"][і].get(к))
print(f"  без змін {300 - len(зм)}, змінилось {len(зм)}; ключі змін: {ключі.most_common(10)}")
