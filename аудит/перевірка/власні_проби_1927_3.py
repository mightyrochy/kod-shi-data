def проба_метали():
    """Срібло, бронза з інтервалом кольору: суд і палітра без вигаданої точки."""
    # 1. Срібний браслет з інтервалом «срібний»
    р_срібло = dict(
        id="срібний-браслет", слот="браслет", тип="браслет", метал="срібло",
        колір_тип="інтервал", lab=None,
        колір_не_вимір=З.не_вимір_кольору(В.ЛЕКСИКОН.get("срібний", В.ЛЕКСИКОН.get("сірий")), "срібний", "shop_word")
    )
    метал_палітри_ср = П.колір_металу(р_срібло)
    метал_суду_ср = bool(_метал_точки((dict(id=р_срібло["id"]), "браслет", None, None, None), {р_срібло["id"]: р_срібло}))
    хибні_ср = [з for з in бюджет_і_відлуння([р_срібло]) if з.get("правило") == "K-COL-05"]
    
    # 2. Бронзові сережки з інтервалом «бронзовий»
    р_бронза = dict(
        id="бронзові-сережки", слот="сережки", тип="сережки", метал="бронза",
        колір_тип="інтервал", lab=None,
        колір_не_вимір=З.не_вимір_кольору(В.ЛЕКСИКОН.get("коричневий", В.ЛЕКСИКОН["жовтий"]), "бронзовий", "shop_word")
    )
    метал_палітри_бр = П.колір_металу(р_бронза)
    метал_суду_бр = bool(_метал_точки((dict(id=р_бронза["id"]), "сережки", None, None, None), {р_бронза["id"]: р_бронза}))
    хибні_бр = [з for з in бюджет_і_відлуння([р_бронза]) if з.get("правило") == "K-COL-05"]
    
    # 3. Метал, але в не-металевому слоті
    р_блуза = dict(
        id="блуза-люрекс", слот="верх", тип="блуза", метал="срібло",
        колір_тип="інтервал", lab=None,
        колір_не_вимір=З.не_вимір_кольору(В.ЛЕКСИКОН.get("срібний", В.ЛЕКСИКОН["сірий"]), "срібний", "shop_word")
    )
    метал_суду_бл = bool(_метал_точки((dict(id=р_блуза["id"]), "верх", None, None, None), {р_блуза["id"]: р_блуза}))

    # 4. Срібний браслет із хроматичною вставкою
    р_вставка = dict(
        р_срібло,
        id="браслет-вставка",
        колір_вставки=[dict(lab=(50, 60, 30), частка=1.0)]
    )
    метал_суду_вст = bool(_метал_точки((dict(id=р_вставка["id"]), "браслет", None, None, None), {р_вставка["id"]: р_вставка}))

    результат = {
        "срібло_палітра": метал_палітри_ср,
        "срібло_суд": метал_суду_ср,
        "срібло_K_COL_05": len(хибні_ср),
        "бронза_палітра": метал_палітри_бр,
        "бронза_суд": метал_суду_бр,
        "бронза_K_COL_05": len(хибні_бр),
        "блуза_суд": метал_суду_бл,
        "вставка_суд": метал_суду_вст
    }
    print("Метали результат:", json.dumps(результат, ensure_ascii=False))
    
    assert метал_палітри_ср is True, "Палітра має бачити срібний браслет металом"
    assert метал_суду_ср is True, "Суд має бачити срібний браслет металом"
    assert not хибні_ср, "Не має бути хибної K-COL-05 для срібла"
    assert метал_палітри_бр is True, "Палітра має бачити бронзові сережки металом"
    assert метал_суду_бр is True, "Суд має бачити бронзові сережки металом"
    assert not хибні_бр, "Не має бути хибної K-COL-05 для бронзи"
    assert метал_суду_бл is False, "Блуза не повинна вважатися металом прикраси"
    assert метал_суду_вст is False, "Хроматична вставка не повинна визначатися як метал"
    return результат


def проба_пул_лише_інтервали():
    """Пул лише з інтервалів дає заміну (обирає інтервал у межах палітри)."""
    палітра = dict(вікна=dict(L=(20, 80), C=(0, 50), сім_ї=dict(усі=[(0, 359.99)])))
    стара = dict(ід="старий-верх", слот="верх")

    інтервал_ок = dict(
        id="синій-інтервал-ок", слот="верх", тип="блуза", колір_тип="інтервал", lab=None,
        колір_не_вимір=dict(свідок="shop_word", вікно=(40, 60, 10, 30, (200, 240)))
    )
    інтервал_поза = dict(
        id="яскравий-інтервал-поза", слот="верх", тип="блуза", колір_тип="інтервал", lab=None,
        колір_не_вимір=dict(свідок="shop_word", вікно=(40, 60, 70, 90, (10, 30)))
    )
    пул = [інтервал_поза, інтервал_ок]

    with patch.object(О, "_цілі", return_value=[стара["ід"]]), \
         patch.object(О._РФ, "запис_каталогу", return_value=dict(id=стара["ід"], слот="верх")), \
         patch.object(О, "_крамниця", return_value=({"верх": пул}, "проба", True, {})), \
         patch.object(О, "_ваги_образу", return_value=dict(сума_сил=0)), \
         patch.object(О._СЧ, "відсутнє_на_фото", side_effect=lambda о, *а: (о, [])), \
         patch.object(О, "_покажчики_вітрини_кроками", return_value=iter(())), \
         patch.object(О, "вітрина", return_value={}):
        
        г = О.зміни_кроками({}, {}, {}, {}, [стара], [стара["ід"]], [], dict(сума_сил=1), палітра)
        try:
            while True: next(г)
        except StopIteration as кінець:
            зміни, звіт = кінець.value

    результат = {
        "спроб": len(звіт["спроби"]),
        "замін": len(зміни),
        "обрана": зміни[0]["нова"] if зміни else None
    }
    print("Пул лише з інтервалів результат:", json.dumps(результат, ensure_ascii=False))
    assert len(зміни) == 1 and зміни[0]["нова"] == інтервал_ок["id"]
    return результат


def проба_невідомий_поруч():
    """Невідомий колір поруч з інтервалом не стає кандидатом."""
    палітра = dict(вікна=dict(L=(20, 80), C=(0, 50), сім_ї=dict(усі=[(0, 359.99)])))
    стара = dict(ід="старий-верх", слот="верх")

    інтервал_ок = dict(
        id="синій-інтервал-ок", слот="верх", тип="блуза", колір_тип="інтервал", lab=None,
        колір_не_вимір=dict(свідок="shop_word", вікно=(40, 60, 10, 30, (200, 240)))
    )
    невідомий = dict(
        id="невідомий-верх", слот="верх", тип="блуза", колір_тип="невідомо", lab=None,
        колір_не_вимір=None
    )
    пул = [невідомий, інтервал_ок]

    with patch.object(О, "_цілі", return_value=[стара["ід"]]), \
         patch.object(О._РФ, "запис_каталогу", return_value=dict(id=стара["ід"], слот="верх")), \
         patch.object(О, "_крамниця", return_value=({"верх": пул}, "проба", True, {})), \
         patch.object(О, "_ваги_образу", return_value=dict(сума_сил=0)), \
         patch.object(О._СЧ, "відсутнє_на_фото", side_effect=lambda о, *а: (о, [])), \
         patch.object(О, "_покажчики_вітрини_кроками", return_value=iter(())), \
         patch.object(О, "вітрина", return_value={}), \
         patch.object(О._РФ, "членство_вікна", wraps=Р.членство_вікна) as членство:
        
        г = О.зміни_кроками({}, {}, {}, {}, [стара], [стара["ід"]], [], dict(сума_сил=1), палітра)
        try:
            while True: next(г)
        except StopIteration as кінець:
            зміни, звіт = кінець.value

    спроби_id = [с.get("нова") or с.get("id") for с in звіт["спроби"]]
    результат = {
        "викликів_членства": членство.call_count,
        "замін": len(зміни),
        "невідомий_у_спробах": невідомий["id"] in спроби_id
    }
    print("Невідомий поруч результат:", json.dumps(результат, ensure_ascii=False))
    assert членство.call_count == 1
    assert len(зміни) == 1 and зміни[0]["нова"] == інтервал_ок["id"]
    assert невідомий["id"] not in спроби_id
    return результат


