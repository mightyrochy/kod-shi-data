"""Зіставляє записані виміри ДО/ПІСЛЯ й початкову серіалізацію брифу."""
import gzip
import json
import pathlib
from collections import Counter


def головна():
    """Рахує зміни джерела без повторного запуску моста чи підміни його даних."""
    тека = pathlib.Path(__file__).resolve().parent
    корінь = тека.parents[2]
    читати = lambda п: json.loads(gzip.decompress(п.read_bytes()))
    до, після = [читати(тека / стан / "середні-персони.json.gz") for стан in ("ДО", "ПІСЛЯ")]
    первісні = читати(корінь / "аудит/перевірка/кольори_9858/доробка/персони.json.gz")
    зміни, початковий_до, початковий_після = Counter(), Counter(), Counter()
    бриф = lambda п: [г.get("поєднання") for г in п]
    for а, б, в in zip(до, після, первісні):
        assert а["вхід"] == б["вхід"] == в["вхід"]
        for поле in ("поєднання", "бриф", "екран"):
            зміни[поле] += а[поле] != б[поле]
        без = в["раніше_без_аналогової"]
        for ціль, поточна in ((початковий_до, а), (початковий_після, б)):
            ціль[("без_аналогової" if без else "з_аналоговою") + ("_змінено" if бриф(поточна["бриф"]) != бриф(в["бриф_ДО"]) else "_незмінно")] += 1
    результат = dict(персон=len(до), змінено=dict(зміни), бриф_проти_першої_спроби_ДО=dict(початковий_до),
                     бриф_проти_першої_спроби_ПІСЛЯ=dict(початковий_після))
    (тека / "зіставлення.json").write_text(json.dumps(результат, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    вади = json.loads((тека / "ДО/вимір.json").read_text(encoding="utf-8"))["гами"][0]["вади"]
    докази = {}
    for з in вади:
        і = з["персона"]
        if первісні[і]["раніше_без_аналогової"]:
            continue
        for г in до[і]["бриф"]:
            for п in г.get("поєднання", []):
                if п["прийом"] == з["прийом"] and all(any(h in к for к in п["кольори"]) for h in з["hex"]):
                    ключ = (і, з["прийом"], tuple(з["hex"]))
                    докази[ключ] = dict(персона=і, вхід=до[і]["вхід"], вада=з, короткий_бриф=п)
    (тека / "суперечність-мірила.json").write_text(json.dumps(list(докази.values()), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    результат["контрприкладів_нульовому_дифу"] = len(докази)
    print(json.dumps(результат, ensure_ascii=False))


if __name__ == "__main__":
    головна()
