"""Зведення знімка пулу прикрас кроку 31 (`пул_металу.py`): на прогін — метал палітри, рядки металу (ранг, мітка),
коди нот рідшого ходу; у перших п'яти кандидатах кожного ювелірного слота — тон коду матеріалу (тепле → золото,
холодне → срібло, рожеве золото — міст, без коду — нема) і рід (рядком металу — «метал», інакше «колір»); слоти, де
обидва роди мають речі, і скільки з них мають обидва роди в перших п'яти. Запуск: python3 пул_звести.py знімок.json …"""
import json, sys, collections as C
ТЕПЛІ = {"золото", "бронза", "латунь", "мідь"}
ХОЛОДНІ = {"срібло", "біле_золото", "платина", "сталь"}
тон = lambda м: "золото" if м in ТЕПЛІ else "срібло" if м in ХОЛОДНІ else "міст" if м else "нема"
for ф in sys.argv[1:]:
    d = json.load(open(ф, encoding="utf-8")); print("==", ф)
    for к, в in d.items():
        к2 = в["композитор"]
        рядки = sorted({р.split("|", 1)[1] for x in к2.values() for р in x["рядки"]})
        ноти = C.Counter(н for x in к2.values() for н in x.get("ноти", ()) if "less_usual" in str(н))
        топ5 = C.Counter(тон(р["метал"]) for x in к2.values() for р in x["речі"][:5])
        # рід — за рядком, яким річ увійшла (знімок кроку 30 роду не пише: рядок металу — роль «метал_палітри»)
        рід = lambda р: р.get("рід") or ("метал" if str(р.get("роль")).startswith("метал_палітри") else "колір")
        з_рядком = [с for с, x in к2.items() if x["рядки"]]
        обидва_є = [с for с in з_рядком if len({рід(р) for р in к2[с]["речі"]}) == 2]
        обидва_5 = [с for с in обидва_є if len({рід(р) for р in к2[с]["речі"][:5]}) == 2]
        без_коду = sum(1 for x in к2.values() for р in x["речі"][:5] if not р["метал"])
        колір_з_кодом = sum(1 for x in к2.values() for р in x["речі"][:5] if рід(р) == "колір" and р["метал"])
        print(f" {к}: метал палітри {в.get('метал_палітри', '?')}; рядки металу {рядки}; ноти {dict(ноти)}; "
              f"перші 5 ({len(к2)} слотів) {dict(топ5)}; без коду металу {без_коду}; роду «колір» з кодом металу "
              f"{колір_з_кодом}; обидва роди в перших 5 — {len(обидва_5)} з {len(обидва_є)} слотів, де обидва мають "
              f"речі (слотів із рядком металу {len(з_рядком)}); "
              f"роди перших 5: {{{', '.join(с + ':' + ''.join(рід(р)[0] for р in к2[с]['речі'][:5]) for с in sorted(к2))}}}")
