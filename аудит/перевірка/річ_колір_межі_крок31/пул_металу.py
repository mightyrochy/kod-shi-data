"""Крок 31 (14465–14467) — пул прикрас на живому шляху моста (`паспорт` → `запити`, як `тест_живого_шляху.py`): `стенд_вх.json`
на `каталог_повний.xml`, гілки «—» і 0, намір conventional, самозвіт металу нема / золото / срібло. Для кожного
прогону — кандидати ювелірних слотів (`palettes.слот_металу`): id, код матеріалу, рядок, яким річ увійшла (`_вікно`).
Однаковий для всіх дерев. Запуск із кореня дерева: python3 -W ignore <шлях> > знімок.json"""
def головна():
    """Повторити живий шлях моста на повному каталозі без виклику моделей."""
    import json, os, sys, tempfile
    _д = os.path.abspath("джерела"); sys.path.insert(0, _д); os.chdir(_д)
    import bridge as B, feed as Ф, palettes as П, тест_живого_шляху as Т  # noqa: E402
    import композитор_збирання as КЗ, композитор_слоти as КС  # noqa: E402
    _ЗЛОВ = {}
    _орк = КС.кандидати_на_слот
    def _обгортка(речі, вікна, слот, *а, **к):
        в = _орк(речі, вікна, слот, *а, **к)
        if П.слот_металу(слот, None):
            _ЗЛОВ.setdefault(слот, dict(рядки=sorted(f'{q.get("роль")}|{q.get("метал")}|{q.get("ранг_риси")}|{bool(q.get("менш_ходове"))}' for q in (вікна or ()) if q.get("слот") in (None, слот) and (q.get("метал") or "метал" in str(q.get("роль")))),
                                        речі=[dict(id=r.get("id"), метал=r.get("метал"), роль=(r.get("_вікно") or {}).get("роль"),
                                                   менш=bool((r.get("_вікно") or {}).get("менш_ходове"))) for r in в[0]]))
        return в
    КЗ._кандидати_на_слот = _обгортка
    вх0 = json.load(open("стенд_вх.json", encoding="utf-8"))
    вх0["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
    вх0["кеш_кольорів"] = os.path.join(tempfile.gettempdir(), "кеш_крок30.json")
    if not os.path.exists(вх0["кеш_кольорів"]): json.dump({}, open(вх0["кеш_кольорів"], "w"))
    вих = {}
    for метал in (None, "золото", "срібло"):
        for гілка in (None, 0):
            вх = dict(вх0, намір="conventional")
            if гілка is not None: вх["гілка"] = гілка
            if метал: вх["драп_сирий"] = {"метал": метал}
            п = json.loads(B.виклик("паспорт", json.dumps(dict(json_моделі=json.dumps(dict(Т.ПАСПОРТ_МОДЕЛІ, намір="conventional"), ensure_ascii=False),
                                                             сценарій=вх.get("сценарій") or {}, вимоги=""), ensure_ascii=False)))
            вх["паспорт"] = п["паспорт"]
            _ЗЛОВ.clear()
            з = json.loads(B.виклик("запити", json.dumps(dict(вх, пакети=1), ensure_ascii=False)))
            канд = з.get("кандидати") or {}
            прик = {}
            for сл, рр in канд.items():
                for р in рр:
                    if П.слот_металу(р.get("слот") or сл, р.get("тип")):
                        в = р.get("_вікно") or {}
                        прик.setdefault(сл, []).append(dict(id=р.get("id"), метал=р.get("метал"), роль=в.get("роль"),
                                                            менш=bool(в.get("менш_ходове"))))
            вих[f"{метал or 'нема'}·{'—' if гілка is None else гілка}"] = dict(пул=з.get("пул_речей"), слоти=sorted(канд), прикраси=прик, композитор=dict(_ЗЛОВ),
                                                                             метал_палітри=(B.спец_останнього_пакета()[0].get("палітра_практична") or {}).get("метал"), помилка=з.get("помилка") or з.get("пул_чому"))
            print(f"Завершено: {метал or chr(8212)} / {гілка}; метал палітри: " + str((B.спец_останнього_пакета()[0].get("палітра_практична") or {}).get("метал")), file=sys.stderr, flush=True)
    json.dump(вих, sys.stdout, ensure_ascii=False)


if __name__ == "__main__":
    головна()
