"""Крок 31 (14414, 14416) — пул прикрас на живому шляху моста, як стенд кроку 30 (`../річ_колір_межі_крок30/пул_металу.py`:
`паспорт` → `запити`, `стенд_вх.json` на `каталог_повний.xml`, намір conventional, самозвіт металу нема / золото / срібло,
гілки «—» і 0). Понад крок 30 знімок пише метал палітри (`palettes.рядки_у_фід`: «золото» / «срібло» / «обидва»), рядки
металу слота з рангом і міткою та коди нот слота. Кандидат — id, код матеріалу, рядок, яким увійшов. Однаковий для
всіх дерев. Запуск із кореня дерева: python3 -W ignore <шлях> [кеш.json] > знімок.json"""
import json, os, sys, tempfile
_д = os.path.abspath("джерела"); sys.path.insert(0, _д); os.chdir(_д)
import bridge as B, feed as Ф, palettes as П, тест_живого_шляху as Т  # noqa: E402
import композитор_збирання as КЗ, композитор_слоти as КС  # noqa: E402
_ЗЛОВ, _ПАЛ = {}, []
_орк, _рядки = КС.кандидати_на_слот, П.рядки_у_фід
def _рядки_обгортка(спец, *а, **к):
    _ПАЛ.append((спец.get("палітра_практична") or {}).get("метал"))
    return _рядки(спец, *а, **к)
def _обгортка(речі, вікна, слот, *а, **к):
    в = _орк(речі, вікна, слот, *а, **к)
    if П.слот_металу(слот, None):
        _ЗЛОВ.setdefault(слот, dict(
            рядки=sorted(f'{q.get("роль")}|{q.get("метал")}|{q.get("ранг_риси")}|{bool(q.get("менш_ходове"))}'
                         for q in (вікна or ()) if q.get("слот") in (None, слот) and q.get("метал")),
            ноти=[з.get("code") for з in (в[1] or ()) if isinstance(з, dict)],
            речі=[dict(id=r.get("id"), метал=r.get("метал"), роль=(r.get("_вікно") or {}).get("роль"),
                       рід="метал" if (r.get("_вікно") or {}).get("метал") else "колір",
                       ранг=(r.get("_вікно") or {}).get("ранг_риси"), менш=bool((r.get("_вікно") or {}).get("менш_ходове")))
                  for r in в[0]]))
    return в
П.рядки_у_фід = _рядки_обгортка
КЗ._кандидати_на_слот = _обгортка
вх0 = json.load(open("стенд_вх.json", encoding="utf-8"))
вх0["каталог"] = Ф.каталог_на_диску("каталог_повний.xml")
вх0["кеш_кольорів"] = sys.argv[1] if len(sys.argv) > 1 else os.path.join(tempfile.gettempdir(), "кеш_крок31.json")
if not os.path.exists(вх0["кеш_кольорів"]): json.dump({}, open(вх0["кеш_кольорів"], "w"))
вих = {}
for метал in (None, "золото", "срібло"):
    for гілка in (None, 0):
        вх = dict(вх0, намір="conventional")
        if гілка is not None: вх["гілка"] = гілка
        if метал: вх["драп_сирий"] = {"метал": метал}
        п = json.loads(B.виклик("паспорт", json.dumps(dict(json_моделі=json.dumps(dict(Т.ПАСПОРТ_МОДЕЛІ, намір="conventional"), ensure_ascii=False),
                                                         сценарій=вх.get("сценарій") or {}, вимоги=""), ensure_ascii=False)))
        вх["паспорт"] = п["паспорт"]
        _ЗЛОВ.clear(); _ПАЛ.clear()
        з = json.loads(B.виклик("запити", json.dumps(dict(вх, пакети=1), ensure_ascii=False)))
        вих[f"{метал or 'нема'}·{'—' if гілка is None else гілка}"] = dict(
            пул=з.get("пул_речей"), метал_палітри=sorted(set(map(str, _ПАЛ))), композитор=dict(_ЗЛОВ),
            помилка=з.get("помилка") or з.get("пул_чому"))
json.dump(вих, sys.stdout, ensure_ascii=False)
