"""Контроль рішень кроку 31 на малих входах; запуск із кореня репозиторію."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path.cwd() / "джерела"))
import композитор_слоти as С
import palettes as П
import accessory as А
import суд_образу as Суд
import внутрішня_мова as М


def головна():
    """Перевірити чергування, ранги, розтяг слів і відсутність висновку з непевної частки."""
    for метал in ("золото", "срібло", "обидва"):
        спец = dict(слоти=dict(намисто=dict(L=(0, 100), сім_я="метал")),
                    палітра_практична=dict(метал=метал, вікна=dict(L=(0, 100), C=(0, 100))))
        рядки = [р for р in П.рядки_у_фід(спец) if р.get("метал")]
        print("метал палітри", метал, [(р["метал"], р["ранг_риси"], bool(р.get("менш_ходове"))) for р in рядки])
        for р in рядки:
            рідше = метал != "обидва" and р["метал"] != метал
            assert р["ранг_риси"] == (3 if рідше else 2)
            assert bool(р.get("менш_ходове")) == рідше

    вікно = dict(слот="намисто", L_min=0, L_max=100, C_min=0, C_max=100,
                 роль="колір", ранг_риси=2)
    метали = [П.рядок_металу("намисто", м, ранг_риси=р)
              for м, р in (("золото", 2), ("срібло", 3))]
    речі = [dict(id=f"{м}{і}", слот="намисто", метал=м, lab=(61, 3, 34), колір_тип="вимір",
                  джерело_кольору="назва_вікно", колір_ім=м)
            for м in ("золото", "срібло") for і in range(4)]
    речі += [dict(id=f"колір{і}", слот="намисто", lab=(61, 3, 34),
                   джерело_кольору="назва_вікно", колір_ім="жовтий",
                   колір_тип="інтервал", колір_не_вимір=dict(
                       свідок="shop_word", вікно=(60, 62, 30, 40, (80, 90))))
             for і in range(6)]
    # Та сама модель не займає другого місця, навіть якщо має інший id.
    речі.append(dict(речі[0], id="інший-артикул", group_id="золото0"))

    for ранг_кольору, перший in ((1, "колір"), (2, "метал"), (3, "метал")):
        пул, _, _ = С.кандидати_на_слот(
            речі, метали + [dict(вікно, ранг_риси=ранг_кольору)], "намисто")
        роди = ["метал" if р["_вікно"].get("метал") else "колір" for р in пул]
        print("ранг кольору", ранг_кольору, "перші десять", роди[:10])
        assert роди[0] == перший
        assert all(a != b for a, b in zip(роди[:12], роди[1:12]))
        assert len(пул) == 14
        assert len({р.get("group_id") or р["id"] for р in пул}) == len(пул)
        ранги = [р["_вікно"]["ранг_риси"] for р in пул if р["_вікно"].get("метал")]
        assert ранги == sorted(ранги), ранги
        assert all(not р.get("метал") for р in пул if not р["_вікно"].get("метал"))
        # Коли кольори скінчилися, лишається метал; жодної втрати кандидата.
        assert роди[-2:] == ["метал", "метал"]

    for тільки in (речі[:8], речі[8:14]):
        пул, _, _ = С.кандидати_на_слот(тільки, метали + [вікно], "намисто")
        assert len(пул) == len(тільки)
    assert С.кандидати_на_слот([], метали + [вікно], "намисто")[0] == []

    for метал, код, поле in (("золото", "jewellery_gold_less_usual_for_cool", "gold_items"),
                             ("срібло", "jewellery_silver_less_usual_for_warm", "silver_items")):
        річ = dict(id=метал, слот="намисто", метал=метал, _вікно=dict(менш_ходове=True))
        нота = С._нота_рідшого_металу([річ], None)
        print("нота", метал, нота)
        assert нота[0]["code"] == код
        assert С._нота_рідшого_металу([річ], метал) is None
        assert поле in М.ЗАЯВИ[код]

    # Старе непевне значення не відкриває A14 і не змінює суд металу.
    елемент = dict(річ="метал", слот="намисто", метал="золото", near=.8, площа=.1)
    еталон = Суд.метали([елемент], {}, драп={"метал": "срібло"})
    for частка in (None, 0, .9):
        змінений = dict(елемент, частка_металу=частка, колір_вставки="синій")
        assert not А.входи_чекліста([змінений])["частка металу в речі"]
        assert Суд.метали([змінений], {}, драп={"метал": "срібло"}) == еталон
    print("A14: без входу; суд металу не залежить від непевних полів")


if __name__ == "__main__":
    головна()
