"""ДО → ПІСЛЯ стенда кроку 30: тон коду матеріалу та два роди по кожному слоту."""
import collections
import json
from pathlib import Path

ТЕПЛІ = {"золото", "бронза", "латунь", "мідь"}
ХОЛОДНІ = {"срібло", "біле_золото", "платина", "сталь"}


def тон(річ):
    """Тон коду матеріалу для незмінного знаменника стенда кроку 30."""
    метал = річ.get("метал")
    return "золото" if метал in ТЕПЛІ else "срібло" if метал in ХОЛОДНІ else "інше" if метал else "нема"


def головна():
    """Звести обидва знімки; ПІСЛЯ мусить задовольняти мірило на кожній гілці."""
    тека = Path(__file__).resolve().parent
    повний_до = json.loads((тека / "пул_до.json").read_text(encoding="utf-8"))
    первинний_до = json.loads((тека / "первинний_до.json").read_text(encoding="utf-8"))
    assert len(повний_до) == len(первинний_до) == 6
    assert {к: в["композитор"] for к, в in повний_до.items()} == {
        к: в["композитор"] for к, в in первинний_до.items()}
    print("Первинний ДО тотожний повному мосту: 6/6 (усі кандидати, порядок і рядки)")
    похибки = []
    поріг_паспорта = []
    for етап in ("до", "після"):
        дані = json.loads((тека / f"пул_{етап}.json").read_text(encoding="utf-8"))
        print(етап.upper())
        for назва, прогін in дані.items():
            assert not прогін["помилка"], (етап, назва, прогін["помилка"])
            слоти = прогін["композитор"]
            assert len(слоти) == 7, (етап, назва, len(слоти))
            перші = collections.Counter(тон(р) for с in слоти.values() for р in с["речі"][:5])
            обидва = доступні = 0
            print(назва, "перші п'ять 7 слотів:", dict(перші))
            for слот, вміст in слоти.items():
                рід = lambda р: "метал" if str(р.get("роль") or "").startswith("метал_палітри:") else "колір"
                всі = collections.Counter(рід(р) for р in вміст["речі"])
                голова = collections.Counter(рід(р) for р in вміст["речі"][:5])
                є_два = len(всі) == 2
                доступні += є_два
                обидва += є_два and len(голова) == 2
                print(" ", слот, "весь пул", dict(всі), "перші 5", dict(голова))
                if етап == "після" and є_два and len(голова) != 2:
                    похибки.append(f"{назва}/{слот}: один рід у перших п'яти")
            print(" слотів із двома родами в перших п'яти:", обидва, "/", доступні)
            if етап != "після": continue
            самозвіт = назва.split("·")[0]
            бажаний = самозвіт if самозвіт in ("золото", "срібло") else прогін["метал_палітри"]
            print(" метал палітри:", прогін["метал_палітри"])
            інший = "золото" if бажаний == "срібло" else "срібло"
            if бажаний in ("золото", "срібло") and перші[бажаний] <= перші[інший]:
                похибки.append(f"{назва}: {бажаний} {перші[бажаний]} <= {інший} {перші[інший]}")
            if самозвіт == "нема" and перші["нема"] < 14:
                поріг_паспорта.append(f"{назва}: без коду металу {перші['нема']} < 14")
    print("Відхилень каталожного мірила наряду:", len(похибки))
    for помилка in похибки: print(помилка)
    print("Додаткова числова умова паспорта 09.11 (поза переліком мірила наряду):")
    for помилка in поріг_паспорта: print(помилка)
    if not поріг_паспорта: print("пройдено")
    raise SystemExit(bool(похибки))


if __name__ == "__main__":
    головна()
