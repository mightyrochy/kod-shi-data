"""Механіка локального запуску: до чотирьох одночасних приладів; код і пороги храповика незмінні.

Стандартний запуск на 32 логічних процесорах завершився чотирма тайм-аутами 900 с (два корені × два дерева).
Вільна пам'ять під час виміру: 4 979 520 KiB із 33 163 924 KiB. Обмежуємо лише виконавчий пул батька;
дочірні прилади запускаються звичайним Python, усі 23 корені та межа часу залишаються в оригінальному храповику.
"""
import concurrent.futures
import runpy
import sys
from pathlib import Path


def головна():
    """Запустити незмінений храповик із меншим одночасним навантаженням."""
    пул = concurrent.futures.ThreadPoolExecutor

    class ЧотириПрилади(пул):
        """Той самий виконавець, максимум чотири завдання одночасно."""

        def __init__(self, max_workers=None, *args, **kwargs):
            """Обмежити лише кількість одночасних процесів приладів."""
            super().__init__(min(max_workers or 4, 4), *args, **kwargs)

    concurrent.futures.ThreadPoolExecutor = ЧотириПрилади
    скрипт = Path(__file__).resolve().parents[3] / "джерела/прилади/храповик_кореня.py"
    sys.path.insert(0, str(скрипт.parent))
    sys.argv = [str(скрипт), "--пр", "--база", "origin/main"]
    runpy.run_path(str(скрипт), run_name="__main__")


if __name__ == "__main__":
    головна()
