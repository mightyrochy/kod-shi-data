def завантажити(код=None):
    модуль = types.ModuleType('прилад')
    модуль.__file__ = str(КОРІНЬ / ПРИЛАД)
    exec(compile(код if код is not None else (КОРІНЬ / ПРИЛАД).read_text(encoding='utf-8'), модуль.__file__, 'exec'),
         модуль.__dict__)
    return модуль


def дерево(тека, модулі):
    дж = Path(тека) / 'джерела'
    дж.mkdir(parents=True, exist_ok=True)
    for ім, текст in {**СПІЛЬНЕ, **модулі}.items():
        (дж / ім).write_text(textwrap.dedent(текст).lstrip('\n'), encoding='utf-8')


def проби(м):
    хиби = []
    for вид, набір, функція in (('Г10', ПРОБИ_Г10, м.місця_г10), ('Г2', ПРОБИ_Г2, м.місця_г2)):
        for ім, модулі, треба in набір:
            with tempfile.TemporaryDirectory() as т:
                дерево(т, модулі)
                є = {(os.path.basename(ф), р) for ф, р, *_ in функція(т)}
                є = {x for x in є if x[0] not in СПІЛЬНЕ} if вид == 'Г10' else є
            print('%s · %s: %s %s' % (вид, ім, 'так' if є == треба else 'НІ', sorted(є)))
            if є != треба:
                хиби.append('%s · %s: є %s, треба %s' % (вид, ім, sorted(є), sorted(треба)))
    return хиби


def прогін(код_приладу, тека):
    """Прилад як у храповику: робоча тека — корінь дерева; останній рядок `місць: N`."""
    with tempfile.NamedTemporaryFile('w', suffix='.py', delete=False, encoding='utf-8') as ф:
        ф.write(код_приладу)
    try:
        вих = subprocess.run([sys.executable, ф.name, str(тека)], cwd=тека, capture_output=True, text=True, check=True)
    finally:
        os.unlink(ф.name)
    return вих.stdout.splitlines()


def головна():
    хиби = проби(завантажити())
    база = subprocess.check_output(['git', 'rev-parse', 'origin/main'], cwd=КОРІНЬ, text=True).strip()
    старий = subprocess.check_output(['git', 'show', '%s:%s' % (база, ПРИЛАД)], cwd=КОРІНЬ).decode('utf-8')
    новий = (КОРІНЬ / ПРИЛАД).read_text(encoding='utf-8')
    до, після = прогін(старий, КОРІНЬ), прогін(новий, КОРІНЬ)
    print('ДО (прилад %s) → ПІСЛЯ на тому самому дереві: %s → %s' % (база[:8], до[-1], після[-1]))
    print('\n'.join(р for р in після if р.startswith(('пункт', 'з них'))))
    рядки = {р.split(' · ')[0] for р in після if ' · пункт ' in р}
    г10 = {р.split(' · ')[0] for р in після if р.endswith('Г10]') or '+Г10' in р}
    г2 = {р.split(' · ')[0] for р in після if 'Г2]' in р}
    for ім, відомі, є in (('Г10', ВІДОМІ_Г10, г10), ('Г2', ВІДОМІ_Г2, г2)):
        нема = sorted('%s:%d' % x for x in відомі if '%s:%d' % x not in є)
        print('відомі місця %s паспорта: %d з %d у лічбі%s' % (ім, len(відомі) - len(нема), len(відомі),
                                                              ('; нема: ' + ', '.join(нема)) if нема else ''))
        if нема:
            хиби.append('%s: нема відомих %s' % (ім, нема))
    старі = {р.split(' · ')[0] for р in до if ' · пункт ' in р}
    if not старі <= рядки:
        хиби.append('ПІСЛЯ загубило місця ДО: %s' % sorted(старі - рядки)[:10])
    нові = sorted(рядки - старі)
    print('нових місць: %d' % len(нові))
    for р in після:
        if р.split(' · ')[0] in нові:
            print('  ' + р)
    print('хиб: %d' % len(хиби))
    for х in хиби:
        print('  ' + х)
    return 1 if хиби else 0


if __name__ == '__main__':
    sys.exit(головна())
