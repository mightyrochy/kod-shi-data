"""Інвентар точок відбору: файл, рядок і передавання спільному механізму, без нового гейта."""
import ast, json, pathlib, subprocess

ТОЧКИ = {'семплер': ['вибрати_зі_слота'], 'композитор_реєстр': ['перемішати'],
          'порядок_запиту': ['перемішати'], 'пакет_моделі': ['номери_речей'],
          'міст_пакет': ['додати_за_запитом'],
          'повнота_образу': ['повнота_набору', 'вердикт_повноти', 'вибір_з_json',
                            'дібрати_кодом', '_ремонт_гейтів']}
МЕХАНІЗМ = {'_ПВ.порядок', '_ПВ.ключ_образу', '_ключ_мети', 'порядок', '_P_.номери_речей'}


def головна():
    """Порівняти погоджені точки живого шляху з базою свіжого main."""
    корінь = pathlib.Path(__file__).resolve().parents[3]
    дані = {}
    for версія in ('f4205efc68b02a716fcf6fae632fed36a4e9301f', 'робоче'):
        рядки = []
        for модуль, функції in ТОЧКИ.items():
            шлях = 'джерела/' + модуль + '.py'
            текст = ((корінь / шлях).read_text(encoding='utf-8') if версія == 'робоче' else
                     subprocess.run(['git', 'show', версія + ':' + шлях], cwd=корінь,
                                    capture_output=True, encoding='utf-8', check=True).stdout)
            for вузол in ast.parse(текст).body:
                if isinstance(вузол, ast.FunctionDef) and вузол.name in функції:
                    виклики = {ast.unparse(n) for n in ast.walk(вузол) if isinstance(n, (ast.Name, ast.Attribute))}
                    делегує = sorted(виклики & МЕХАНІЗМ)
                    рядки.append(dict(файл=шлях, рядок=вузол.lineno, функція=вузол.name,
                                      механізм=делегує, обхід=not bool(делегує)))
        дані[версія] = dict(точок=len(рядки), обходів=sum(r['обхід'] for r in рядки), місця=рядки)
    print(json.dumps(дані, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    головна()
