"""Зберігає компактні факти парного браузерного повтору з повних звітів і журналів стенда."""
import json
import os
from pathlib import Path
import re


if __name__ == "__main__":
    докази = Path(__file__).resolve().parent
    результат = {}
    for стан in ("до", "після"):
        повний = json.loads((Path(os.environ["TEMP"]) / ("е2-браузер-" + стан + "-вердикти.json"))
                            .read_text(encoding="utf-8"))
        журнал = (докази / ("браузер-" + стан + ".txt")).read_text(encoding="utf-8")
        проксі = (докази / ("браузер-" + стан + "-проксі.txt")).read_text(encoding="utf-8")
        руки = []
        for прогін in повний["прогони"]:
            for в in прогін["вердикти"]:
                if в["рука"] not in ("1", "2"):
                    continue
                руки.append({"рука": в["рука"], "свідомі": в.get("свідомі"),
                    "свідомі_ід": в.get("свідомі_ід"),
                    "речі": [{к: р.get(к) for к in ("id", "назва", "назва_крамниці")}
                              for р in в.get("речі_образу", [])]})
        схожості = [float(с) for с in re.findall(r"схожість ([0-9.]+)", проксі)]
        л4 = next(р for р in журнал.splitlines() if "колонка" in р and "(Л-4)" in р)
        результат[стан] = {"Л4_пройдено": "✔" in л4,
            "провалів_стенда": int(re.search(r"ВПАЛО (\d+)", журнал)[1]),
            "провали": [р.strip() for р in журнал.splitlines() if р.startswith("  ✗ ")],
            "без_тексту_в_ходах": sum(str(р["свідомі"]).count("— без тексту") for р in руки),
            "зіставлень": len(схожості), "схожість_мін": min(схожості),
            "схожість_макс": max(схожості),
            "нижче_0_9": [р for р in проксі.splitlines() if (м := re.search(r"схожість ([0-9.]+)", р))
                          and float(м[1]) < 0.9], "руки": руки}
    (докази / "браузер-порівняння.json").write_text(
        json.dumps(результат, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    for стан, р in результат.items():
        print(стан, "Л-4:", р["Л4_пройдено"], "без тексту:", р["без_тексту_в_ходах"],
              "провалів:", р["провалів_стенда"], "схожість:", р["схожість_мін"], "…", р["схожість_макс"])
