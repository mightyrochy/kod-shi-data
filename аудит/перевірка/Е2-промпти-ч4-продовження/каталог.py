"""Порівнює збагачення на каталозі та збережених відповідях без виклику моделі."""
import gzip
import json
from pathlib import Path
import subprocess
import sys
import types

КОРІНЬ = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(КОРІНЬ / "джерела"))
import feed as Ф
import жнива_збагачення as ПІСЛЯ
import спільні_вимоги as ВИМОГИ
from жнива_промпти import _КРІЙ_ОДЯГУ, _ЗАГ_ВІЗЕРУНОК


def головна():
    """Міряє довжини всіх типів, спільні настанови та незмінність читача записів."""
    база = sys.argv[1]
    шлях = "джерела/жнива_збагачення.py"
    текст = subprocess.check_output(["git", "show", база + ":" + шлях], cwd=КОРІНЬ)
    до = types.ModuleType("збагачення_до")
    до.__file__ = str(КОРІНЬ / шлях)
    exec(compile(текст, до.__file__, "exec"), до.__dict__)
    речі, _ = Ф.читати_yml(Ф.каталог_на_диску("каталог_повний.xml"), показ=False)
    типи = sorted({ПІСЛЯ.тип_для_промпту(р)[0] for р in речі})
    різниці = set()
    for тип in типи:
        старий, новий = до._промпт(тип), ПІСЛЯ._промпт(тип)
        різниці.add(len(старий) - len(новий))
        assert len(новий) < len(старий), тип
        assert новий.endswith(ПІСЛЯ.ШАБЛОН) and до.ШАБЛОН == ПІСЛЯ.ШАБЛОН
        for настанова in (_КРІЙ_ОДЯГУ, _ЗАГ_ВІЗЕРУНОК):
            розгорнута = (настанова.replace("{крої}", ", ".join(ПІСЛЯ.КРОЇ))
                         .replace("{візерунки}", ", ".join(ПІСЛЯ.ВІЗЕРУНКИ)))
            assert новий.count(розгорнута) == 1, (тип, настанова)
        for ключ in ("{тип}", "{крої}", "{візерунки}", "{кольори}", "{матеріали}", "{довжини}", "{шаблон}"):
            assert ключ not in новий, (тип, ключ)
    with gzip.open(КОРІНЬ / "джерела/каталог_збагачення.json.gz", "rt", encoding="utf-8") as в:
        записи = json.load(в)
    розбіжності = sum(до.нормалізувати(р) != ПІСЛЯ.нормалізувати(р) for р in записи.values())
    assert розбіжності == 0
    вимоги_до = types.ModuleType("вимоги_до")
    exec(subprocess.check_output(["git", "show", база + ":джерела/спільні_вимоги.py"], cwd=КОРІНЬ),
         вимоги_до.__dict__)
    assert ВИМОГИ.КОДИ_GOAL_EXTRA == вимоги_до.КОДИ_GOAL_EXTRA
    assert ВИМОГИ.ПОЛЯ == вимоги_до.ПОЛЯ
    print(f"База: {база}; каталог: {len(речі)} речей, {len(типи)} типів.")
    print(f"Усі запити коротші на {sorted(різниці)} символів; шаблон незмінний.")
    print("Спільні настанови крою й візерунку присутні рівно один раз; підстановки завершені.")
    print(f"Записаних відповідей: {len(записи)}; розбіжностей читача: {розбіжності}.")
    print("goal_extra та всі спільні описи й настанови полів побайтово тотожні.")
    print("Вплив на відповіді моделі не виміряно.")


if __name__ == "__main__":
    головна()
