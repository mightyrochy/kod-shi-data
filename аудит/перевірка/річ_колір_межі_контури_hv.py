"""Звіряє перенесення всього класу скінченних внутрішніх H/V-граней.

Власна перевірка виконавця; не незалежне приймання сімей чи похибки між пробами.
"""
import hashlib
import importlib.util
import json
import math
from pathlib import Path
import unittest


КОРІНЬ = Path(__file__).resolve().parents[2]


def завантажити(назва, шлях):
    """Завантажує лабораторний метод або попередню перевірку без запуску CLI."""
    специфікація = importlib.util.spec_from_file_location(назва, шлях)
    модуль = importlib.util.module_from_spec(специфікація)
    специфікація.loader.exec_module(модуль)
    return модуль


МОДУЛЬ = завантажити("контури_hv", КОРІНЬ / "джерела/лабораторія/колір_сім_ї_контури_hv.py")
ПОПЕРЕДНЯ = завантажити("перевірка_контурів", Path(__file__).with_name("річ_колір_межі_контури.py"))
ОСНОВА = МОДУЛЬ.ОСНОВА


class ПеревіркаКонтурівГраней(unittest.TestCase):
    """Звіряє облік, параметризацію, геометрію, числову похибку й походження."""

    @classmethod
    def setUpClass(клас):
        """Читає округлений артефакт і готує пряме перетворення H/V/C."""
        клас.бібліотека = ОСНОВА.залежності()
        клас.перетворити = staticmethod(ОСНОВА.зробити_перетворення(клас.бібліотека))
        клас.вхід = json.loads(МОДУЛЬ.ВХІД.read_text(encoding="utf-8"))
        клас.вихід = json.loads(МОДУЛЬ.ВИХІД.read_text(encoding="utf-8"))
        клас.попередній = json.loads(ОСНОВА.ВИХІД.read_text(encoding="utf-8"))

    def test_облік_всього_класу(self):
        """Самостійно вибирає клас за геометрією, без предиката генератора."""
        очікувані = set()
        for i, грань in enumerate(self.вхід["межі"]):
            if грань["вісь"] not in "HV":
                continue
            перша, C = грань["інтервали"]
            V = перша if грань["вісь"] == "H" else [грань["координата"]] * 2
            if isinstance(C[1], (int, float)) and C[0] > 0 and 0 < V[0] <= V[1] < 10:
                очікувані.add(i)
        готові = [x["грань"] for x in self.вихід["грані"]]
        раніше = self.вихід["раніше"]
        відкладені = [x["грань"] for x in self.вихід["відкладені"]]
        self.assertEqual(set(готові), очікувані)
        self.assertEqual(раніше, sorted(x["грань"] for x in self.попередній["грані"]))
        self.assertEqual(sorted(готові + раніше + відкладені), list(range(len(self.вхід["межі"]))))
        self.assertTrue(all(x["причина"] for x in self.вихід["відкладені"]))
        print(f"Облік: H/V {len(готові)}; раніше C {len(раніше)}; відкладено {len(відкладені)}")

    def test_повне_покриття(self):
        """Звіряє всі відкриті смуги незалежно від адаптивної сітки методу."""
        for грань in self.вихід["грані"]:
            джерело = self.вхід["межі"][грань["грань"]]
            self.assertEqual(грань["джерело"], джерело)
            ділянки = [{"HV": x["параметри"]} for x in грань["ділянки"]]
            ПОПЕРЕДНЯ.звірити_покриття(self, джерело["інтервали"], ділянки)

    def test_параметризація(self):
        """Звіряє порядок H/V/C на синтетичному несиметричному перетворенні."""
        def координати(H, V, C):
            """Повертає кожний аргумент окремо для виявлення перестановки осей."""
            return H, V, C

        self.assertEqual(МОДУЛЬ.параметризувати(координати, "H")(3, 7, 21), (21, 3, 7))
        self.assertEqual(МОДУЛЬ.параметризувати(координати, "V")(21, 7, 3), (21, 3, 7))
        with self.assertRaises(ValueError):
            МОДУЛЬ.координати_джерела("C", 7, 21, 3)

    def test_вузли_renotation_не_перетинаються(self):
        """Кожна початкова ділянка лежить між вузлами обох вільних координат."""
        for грань in self.вихід["грані"]:
            джерело = грань["джерело"]
            вузли = range(11) if джерело["вісь"] == "H" else [2.5 * i for i in range(41)]
            for перша, C in МОДУЛЬ.початкові_ділянки(джерело):
                self.assertFalse(any(перша[0] < x < перша[1] for x in вузли))
                self.assertFalse(any(C[0] < x < C[1] for x in range(0, int(C[1]) + 2, 2)))

    def test_область_renotation(self):
        """Звіряє стелю C на H/V-смугах без поділу за C генератора."""
        from colour.notation.munsell import (maximum_chroma_from_renotation,
                                            munsell_colour_to_munsell_specification)
        смуг = 0
        запас = math.inf
        for грань in self.вихід["грані"]:
            джерело = грань["джерело"]
            перша, C = джерело["інтервали"]
            вузли = range(11) if джерело["вісь"] == "H" else [2.5 * i for i in range(41)]
            краї = [перша[0]] + [x for x in вузли if перша[0] < x < перша[1]] + [перша[1]]
            найменший = math.inf
            for низ, верх in zip(краї, краї[1:]):
                H = джерело["координата"] if джерело["вісь"] == "H" else (низ + верх) / 2
                V = ((верх if верх > 9 else (низ + верх) / 2)
                     if джерело["вісь"] == "H" else джерело["координата"])
                h, V, _, код = munsell_colour_to_munsell_specification(ОСНОВА.позначення(H, V, C[1]))
                стеля = maximum_chroma_from_renotation([h, V, код])
                self.assertGreaterEqual(стеля, C[1])
                найменший = min(найменший, стеля - C[1])
                смуг += 1
            self.assertAlmostEqual(найменший, грань["область_renotation"]["мінімальний_запас_C"])
            запас = min(запас, найменший)
        print(f"Область: {смуг} H/V-смуг; найменший запас C {запас}")

    def test_відмова_поза_областю(self):
        """Скінченність сама по собі не дозволяє екстраполяцію за стелю C."""
        with self.assertRaises(ValueError):
            МОДУЛЬ.перевірити_область({"вісь": "V", "координата": 5,
                                     "інтервали": [[50, 51], [200, 202]]})

    def test_походження(self):
        """Звіряє транзитивне походження всіх джерел і числових алгоритмів."""
        for запис in self.вихід["походження"] + self.вихід["походження_перетворення"]:
            назва = запис["файл"]
            if назва.startswith("colour/"):
                шлях = Path(self.бібліотека.__file__).parent / назва.removeprefix("colour/")
            else:
                шлях = МОДУЛЬ.ВХІД.parent / назва
                if not шлях.is_file():
                    шлях = ОСНОВА.ДЖЕРЕЛА / назва
            хеш = hashlib.sha256(шлях.read_text(encoding="utf-8").encode("utf-8")).hexdigest()
            self.assertEqual(хеш, запис["sha256_lf"], назва)

    def test_координати_округленого_файла(self):
        """Звіряє вузли та дві нові внутрішні точки кожної записаної ділянки."""
        максимуми = [0.0] * 4
        проб = 0
        for грань in self.вихід["грані"]:
            джерело = грань["джерело"]
            def пряме(перша, C):
                """Відновлює координати джерела окремо від адаптера генератора."""
                if джерело["вісь"] == "H":
                    return self.перетворити(джерело["координата"], перша, C)
                return self.перетворити(перша, джерело["координата"], C)

            for ділянка in грань["ділянки"]:
                (a, b), (c, d) = ділянка["параметри"]
                for параметри, вузол in zip(((a, c), (b, c), (b, d), (a, d)), ділянка["вузли"]):
                    lab, координати = пряме(*параметри)
                    self.assertLess(math.dist(lab, вузол[0]), 1e-8)
                    self.assertLess(max(ОСНОВА.похибки((lab, координати), вузол)), 1e-8)
                for u, v in ((0.137, 0.619), (0.863, 0.381)):
                    точне = пряме(a + u * (b - a), c + v * (d - c))
                    lab = ОСНОВА.наблизити([x[0] for x in ділянка["вузли"]], u, v)
                    вимір = ОСНОВА.похибки(точне, (lab, ОСНОВА.координати_з_lab(lab)))
                    максимуми = list(map(max, максимуми, вимір))
                    проб += 1
        self.assertTrue(all(x <= ціль for x, ціль in zip(максимуми, self.вихід["цілі_похибки"])))
        print(f"Округлений файл: {проб} інших внутрішніх проб; максимуми ΔLab76/θ/L*/C*: {максимуми}")

    def test_записані_похибки(self):
        """Звіряє скінченність усіх вузлів і числові цілі всіх записаних проб."""
        for грань in self.вихід["грані"]:
            for ділянка in грань["ділянки"]:
                for вид in ("контроль", "перевірка"):
                    for вимір, ціль in zip(ділянка[вид], self.вихід["цілі_похибки"]):
                        self.assertTrue(0 <= вимір <= ціль)
                self.assertTrue(all(math.isfinite(x) for вузол in ділянка["вузли"]
                                    for простір in вузол for x in простір))

    def test_стикування_ділянок(self):
        """Повторює вимір усіх внутрішніх стиків спільним попереднім методом."""
        оригінал = self.вихід
        self.вихід = {"цілі_похибки": оригінал["цілі_похибки"], "грані": [
            {"ділянки": [dict(x, HV=x["параметри"]) for x in грань["ділянки"]]}
            for грань in оригінал["грані"]]}
        try:
            ПОПЕРЕДНЯ.ПеревіркаКонтурів.test_стикування_ділянок(self)
        finally:
            self.вихід = оригінал


if __name__ == "__main__":
    unittest.main()
