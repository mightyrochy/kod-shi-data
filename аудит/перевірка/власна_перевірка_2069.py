def запустити_підпроцес(дерево, сценарій, сім):
    середовище = dict(os.environ, PYTHONUTF8="1", PYTHONIOENCODING="utf-8")
    команда = [
        sys.executable,
        str(Path(__file__).resolve()),
        "--worker",
        str(дерево),
        сценарій,
        сім,
    ]
    вивід = subprocess.check_output(команда, cwd=КОРІНЬ, env=середовище).decode("utf-8")
    for рядок in вивід.splitlines():
        if рядок.startswith("JSON_OUTPUT:"):
            return json.loads(рядок[len("JSON_OUTPUT:") :])
    raise RuntimeError(f"Не знайдено JSON_OUTPUT у виводі:\n{вивід}")


def розпакувати_до_каталог(тимчасова):
    архів = subprocess.check_output(
        ["git", "archive", "a136a841db8fed6703c17866166514729f2875eb", "zhnyvarka"],
        cwd=КОРІНЬ,
    )
    with tarfile.open(fileobj=io.BytesIO(архів)) as потік:
        потік.extractall(тимчасова, filter="data")
    return Path(тимчасова) / "zhnyvarka"


def перевірити_все():
    журнал_рядки = []
    def лог(рядок=""):
        print(рядок)
        журнал_рядки.append(рядок)

    with tempfile.TemporaryDirectory(prefix="dorobka-do-") as td_до:
        дерево_до = розпакувати_до_каталог(td_до)
        дерево_після = КОРІНЬ / "zhnyvarka"

        лог("=================================================================")
        лог("  НЕЗАЛЕЖНА ПЕРЕВІРКА ДОРОБКИ #2069 (Woo та Shopify)")
        лог("=================================================================")

        # 1. Відтворення знахідок ДО vs ПІСЛЯ
        for сім in ("woo", "shopify"):
            лог(f"\n--- [1] Знахідки рецензії Codex: сім'я {сім.upper()} ---")

            # Знахідка 1: додано товар після завершеного проходу
            р_до = запустити_підпроцес(дерево_до, "додано_товар", сім)
            р_після = запустити_підпроцес(дерево_після, "додано_товар", сім)
            лог(f"1. Додано товар:")
            лог(f"   ДО:    HTTP={р_до['запити']}, карток={р_до['карток']}/4 (втрата 4-го товару: {р_до['запити'] == [] and р_до['карток'] == 3})")
            лог(f"   ПІСЛЯ: HTTP={р_після['запити']}, карток={р_після['карток']}/4, сума={р_після['сума']}")
            assert р_до["запити"] == [] and р_до["карток"] == 3
            assert р_після["запити"] == [1, 2, 3] and р_після["карток"] == 4 and р_після["сума"]

            # Знахідка 2: очищено JSONL після завершеного проходу
            р_до2 = запустити_підпроцес(дерево_до, "очищено_jsonl", сім)
            р_після2 = запустити_підпроцес(дерево_після, "очищено_jsonl", сім)
            лог(f"2. Очищено JSONL:")
            лог(f"   ДО:    HTTP={р_до2['запити']}, карток={р_до2['карток']}/3 (втрата підтверджена: {р_до2['карток'] == 0}, записано суму порожнього: {р_до2['сума']})")
            лог(f"   ПІСЛЯ: HTTP={р_після2['запити']}, карток={р_після2['карток']}/3 (відбудовано з кешу!), сума={р_після2['сума']}")
            assert р_до2["запити"] == [] and р_до2["карток"] == 0 and р_до2["сума"]
            assert р_після2["запити"] == [] and р_після2["карток"] == 3 and р_після2["сума"]

        # 2. Свої випадки
        for сім in ("woo", "shopify"):
            лог(f"\n--- [2] Свої сценарії: сім'я {сім.upper()} ---")

            # Сценарій 1: Товар зник між проходами
            р1 = запустити_підпроцес(дерево_після, "товар_зник", сім)
            лог(f"Сценарій 1 (товар зник з крамниці): HTTP={р1['запити']}, товарів_у_новому_кеші={р1['товарів_у_новому_кеші']}/3, зниклий_товар_у_новому_кеші={р1['зниклий_товар_у_новому_кеші']}, сума={р1['сума']}")
            assert р1["запити"] == [1, 2, 3] and р1["товарів_у_новому_кеші"] == 3 and not р1["зниклий_товар_у_новому_кеші"] and р1["сума"]

            # Сценарій 2: Пошкоджено посеред рядка
            р2 = запустити_підпроцес(дерево_після, "журнал_пошкоджено_посеред_рядка", сім)
            лог(f"Сценарій 2 (пошкоджено посеред рядка): HTTP={р2['запити']}, карток={р2['карток']}/3, пошкоджено={р2.get('пошкоджено')}, сума={р2['сума']}")
            assert р2["запити"] == [] and р2["карток"] == 3 and р2["сума"]

            # Сценарій 3: Кеш є, журналу нема
            р3 = запустити_підпроцес(дерево_після, "кеш_є_журналу_нема", сім)
            лог(f"Сценарій 3 (кеш сторінок є, журналу нема): HTTP={р3['запити']}, карток={р3['карток']}/3, відбудовано={р3['файл_існує']}, сума={р3['сума']}")
            assert р3["запити"] == [] and р3["карток"] == 3 and р3["сума"] and р3["файл_існує"]

            # Сценарій 4: Стара позиція з маркером кінця без суми
            р4 = запустити_підпроцес(дерево_після, "стара_позиція_без_суми", сім)
            лог(f"Сценарій 4 (маркер кінця без суми): завершено() -> {р4['завершено_метод']}, новий_завершено={р4['новий_завершено']}, сторінка={р4['нова_сторінка']}")
            assert р4["завершено_метод"] is False and р4["новий_завершено"] is False and р4["нова_сторінка"] == 1

            # Сценарій 5: Два запуски поспіль після завершення
            р5 = запустити_підпроцес(дерево_після, "два_запуски_поспіль", сім)
            лог(f"Сценарій 5 (два запуски поспіль): залишок_керівника={р5['залишок_керівника']}, магазинів_до_запуску={р5['магазинів_до_запуску']}, стан_код={р5['стан_код']}")
            assert р5["залишок_керівника"] == 0 and р5["магазинів_до_запуску"] == 0 and р5["стан_код"] == "CATALOG"

        лог("\n=================================================================")
        лог("  УСІ СЦЕНАРІЇ ВЛАСНОЇ ПЕРЕВІРКИ УСПІШНІ (код 0)!")
        лог("=================================================================")

    вихід_лог = КОРІНЬ / "аудит" / "перевірка" / "власна_перевірка_2069.txt"
    вихід_лог.write_text("\n".join(журнал_рядки) + "\n", encoding="utf-8")


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "--worker":
        виконати_робочий(sys.argv[2], sys.argv[3], sys.argv[4])
    else:
        перевірити_все()
