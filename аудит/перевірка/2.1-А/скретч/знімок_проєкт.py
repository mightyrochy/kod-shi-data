import колір_відношення as КВ, річ_з_фото as РФ, colorspace as cs
def згасання(хрома):
    кут = math.degrees(2.0 * math.asin(min(1.0, КВ.ΔH_КРАЮ / (2.0 * max(хрома, 1e-6)))))
    return min(кут, КВ.ЗАПАС_ПРИГЛУШЕНИХ) / КВ._Z_КІНЦЯ
край = lambda d, пів, σ: 0.5 * (1.0 + math.erf((пів - d) / (σ * math.sqrt(2.0))))
def сила_в_дузі(р, дуга):
    if р is None or р["дуга"] is None: return КВ.НЕВІДОМО
    (ц, пів), σ = КВ._параметри_дуги(дуга), (згасання(р["C"][0]), згасання(р["C"][1])); д = КВ._розкид_дуг(р["дуга"], (ц, ц))
    return (min(край(д[1], пів, с) for с in σ), max(край(д[0], пів, с) for с in σ))
КВ.сила_в_дузі = сила_в_дузі
КВ.сила_точки_в_дузі = lambda C, h, дуга: край(КВ._кут(h, КВ._параметри_дуги(дуга)[0]), КВ._параметри_дуги(дуга)[1], згасання(C))
def членство_в_палітрі(lab, П):
    from колір_річ import нейтраль, запис_кольору
    import palettes as _ПЛ
    L, C_, h = cs.lch(tuple(lab)); в = П["вікна"]
    чL = cs.soft(L, в["L"][0], в["L"][1], РФ.ШИРИНА_L)
    if нейтраль(tuple(lab)) is not None:
        сила, чC, чh = чL, None, None
        роль = "темна нейтраль" if L < 35 else ("світла нейтраль" if L > 80 else "нейтраль"); сім = "нейтраль"
    else:
        чC = cs.soft(C_, в["C"][0], в["C"][1], РФ.ШИРИНА_C)
        дуги = [д for сім_, дд in в["сім_ї"].items() if сім_ != "очі" for д in дд]
        чh = min(1.0, 0.5 * max([КВ.сила_точки_в_дузі(C_, h, д) for д in дуги] or [0.0]) / КВ.КІНЕЦЬ_ЗГАСАННЯ)
        со = КВ.сила_сім_ї_очей(запис_кольору(dict(lab=tuple(lab))), в.get("очі"))[0] if в.get("очі") else 0.0
        очі = 1.0 if со >= 0.5 else со
        чh = max(чh, очі); сила = чL * чC * чh
        роль = "акцент (сім'я твоїх очей)" if очі >= 0.99 else "колір"; сім = (_ПЛ.сім_я_тону(h) or ("інша",))[0]
    стан = "у палітрі" if сила >= РФ.У_ПАЛІТРІ else ("на межі" if сила >= РФ.НА_МЕЖІ else "поза палітрою")
    return dict(сила=round(сила, 3), роль=роль, стан=стан, сім_я=сім,
                частки=dict(L=round(чL, 3), C=(round(чC, 3) if чC is not None else None), тон=(round(чh, 3) if чh is not None else None)))
РФ.членство_в_палітрі = членство_в_палітрі
