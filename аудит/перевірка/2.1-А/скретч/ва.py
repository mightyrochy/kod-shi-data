"""Скретч: варіант (а') — `сила_в_дузі` зі згасанням сталої ΔH* без підлоги σ 5° (насичені — різка межа, приглушені —
до 10°), K-PAL-17 на тій самій силі. Зміни проти main: суд (зріз кінця згасання) на парах вар.pkl, K-PAL-17 — стан."""
import math, колір_відношення as КВ
from statistics import NormalDist
def згасання(хрома):
    кут = math.degrees(2.0 * math.asin(min(1.0, КВ.ΔH_КРАЮ / (2.0 * max(хрома, 1e-6)))))
    return min(кут, КВ.ЗАПАС_ПРИГЛУШЕНИХ) / КВ._Z_КІНЦЯ
def сила_точки(C, h, дуга):
    ц, пів = КВ._параметри_дуги(дуга)
    return КВ.у_вікні(КВ._кут(h, ц), (0.0, пів, False), згасання(C))

def членство(с):
    """Сила тону → частка тону K-PAL-17: половина на кінці згасання (межа суду «поза», `у_вікнах_меж`), повна — удвічі вище;
    з повними L*, C* «у палітрі» ⟺ суд «так» (сила ≥ кінця згасання). Та сама форма, що `_дуга_членство` (2·плече)."""
    return min(1.0, 0.5 * с / КВ.КІНЕЦЬ_ЗГАСАННЯ)

def членство_очей(с):
    """Сім'я очей → частка тону K-PAL-17: «так» вердикту суду (`у_сім_ї_очей`, зріз 0.5) — 1 (роль «акцент»), інакше сила."""
    return 1.0 if с >= 0.5 else с

def край(d, пів, σ):
    """Сила «відстань тону d до центру дуги — у пів-ширині» з розмитою межею: Φ((пів − d)/σ) — на краю рівно 0.5."""
    return 0.5 * (1.0 + math.erf((пів - d) / (σ * math.sqrt(2.0))))
def сила_в_дузі(р, дуга, згас=None):
    """`колір_відношення.сила_в_дузі` з одностороннім краєм (`край`) і згасанням `згас` (типово — нинішнє)."""
    if р is None or р["дуга"] is None:
        return КВ.НЕВІДОМО
    згас = згас or КВ._згасання; ц, пів = КВ._параметри_дуги(дуга)
    д = КВ._розкид_дуг(р["дуга"], (ц, ц)); σ = (згас(р["C"][0]), згас(р["C"][1]))
    return (min(край(д[1], пів, с) for с in σ), max(край(д[0], пів, с) for с in σ))
