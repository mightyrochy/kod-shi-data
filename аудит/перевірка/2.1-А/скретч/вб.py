"""Скретч: варіант (б) — «тон у вікні» колом ∩ ΔH* (форма `колір_відношення._диск`), ширина — градуси кола; ширшання
приглушених і темних — (1 − τ) у межах підтону. Вікно: (центр кола, пів-ширина кола)."""
import math, colorspace as cs, колір_відношення as КВ
ПРОПОРЦІЯ_ΔH = КВ.ВІКНА_ΔH["same_hue"][0] / КВ.ДУГА_ВІДЛУННЯ    # 3 ΔH* на 15° кола (ВІКНА_ΔH: 3 : 9 : 15 ↔ 15 : 45 : 75)
def вікно_з_дуги(д, роль=True):
    """Роль (h ± пів CIELAB у СХЕМИ) → (k(центр), пів як градуси кола); сім'я (категорія) → точний образ дуги на колі."""
    ц, пів = КВ._параметри_дуги(д)
    if роль: return (cs.у_коло_художника(ц), пів)
    кл, кх = cs.у_коло_художника(д[0]), cs.у_коло_художника(д[1]); ш = ((кх - кл) % 360) / 2
    return ((кл + ш) % 360, ш)
def тепло(k): return math.cos(math.radians(k - КВ.ТЕПЛИЙ_ПОЛЮС))
def сила(L, C, h, вікно, ширшання=True, сигма=КВ.СІГМА_МЕЖІ):
    кц, пів = вікно; k = cs.у_коло_художника(h); dk = КВ._кут(k, кц)
    к = КВ.у_вікні(dk, (0.0, пів, False), сигма)
    hц = cs.з_кола_художника(кц); dh = 2 * C * math.sin(math.radians(КВ._кут(h, hц)) / 2)
    н = КВ.у_вікні(dh, (0.0, ПРОПОРЦІЯ_ΔH * пів, False), КВ.СІГМА_ΔH) * КВ.у_вікні(dk, (0.0, КВ.МЕЖА_БЛИЗЬКИХ, False), КВ.СІГМА_МЕЖІ)
    с = max(к, н)
    if ширшання:
        р = dict(L=(L, L), C=(C, C), дуга=(h, h)); τ = КВ.певність_тону(р)[0]
        підтон = 1.0 if тепло(k) * тепло(кц) > 0 else 0.0
        с = max(с, (1 - τ) * підтон * КВ.у_вікні(dk, (0.0, КВ.МЕЖА_БЛИЗЬКИХ, False), КВ.СІГМА_МЕЖІ))
    return с
