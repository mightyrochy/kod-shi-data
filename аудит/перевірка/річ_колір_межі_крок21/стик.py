"""Крок 21, рішення менеджера 06.11 (13776): вердикт на стику — усі значні сім'ї. База (`git show <ревізія>`) проти
дерева на каталозі: речей на стику (≥ 3 значних) ДО → ПІСЛЯ, зміни вердикту й «однієї сім'ї» (`сім_я_кольору`),
сім'ї, що ввійшли у вердикт; 40 граничних свотчів `мірило.json` кроку 05.11 — вердикт ДО → ПІСЛЯ.
Запуск із кореня (розпакований `джерела/каталог_повний.xml`):
python3 -W ignore аудит/перевірка/річ_колір_межі_крок21/стик.py <ревізія>"""
import collections, importlib.util, json, subprocess, sys, tempfile
sys.path.insert(0, "джерела")
import колір_річ as КР, колір_тон as Т, фід_каталог as ФК
т = subprocess.run(["git", "show", f"{sys.argv[1]}:джерела/колір_тон.py"], check=True, capture_output=True).stdout
ф = tempfile.NamedTemporaryFile(suffix=".py", delete=False); ф.write(т); ф.close()
сп = importlib.util.spec_from_file_location("кт_база", ф.name); Д = importlib.util.module_from_spec(сп); сп.loader.exec_module(Д)
З = Т.РЕЄСТР["значна_сила"]["val"]


def ім(в):
    return "+".join(к for к, _ in в)


кат = ФК.прочитати_каталог(ФК.каталог_на_диску("каталог_повний.xml"), 0)["каталог"]
всього = змін = змін_однієї = стик_до = стик_після = 0
довжини_до, довжини_після, ввійшли, одна = collections.Counter(), collections.Counter(), collections.Counter(), collections.Counter()
for р in кат:
    lab = КР.точка_кольору(р)
    if lab is None:
        continue
    lab = [float(x) for x in lab]; всього += 1
    до, після = Д.сім_ї_кольору(lab), Т.сім_ї_кольору(lab)
    довжини_до[len(до)] += 1; довжини_після[len(після)] += 1
    стик_до += sum(1 for к, с in Д.сили_сімей(lab).items() if к != Т.НЕВІДОМО and с >= З) >= 3
    стик_після += Т.на_стику(після)
    if до != після:
        змін += 1
        for к, _ in після[len(до):]:
            ввійшли[к] += 1
    о_до, о_після = Д.сім_я_кольору(lab)[0], Т.сім_я_кольору(lab)[0]
    if о_до != о_після:
        змін_однієї += 1; одна[(о_до, о_після)] += 1
print(f"речей з виміром: {всього} | на стику (≥ 3 значних): {стик_до} → {стик_після}")
print(f"сімей у вердикті → речей: {dict(sorted(довжини_до.items()))} → {dict(sorted(довжини_після.items()))}")
print(f"вердикт змінився: {змін}; увійшли у вердикт: {dict(ввійшли.most_common())}")
print(f"`сім_я_кольору` змінилась: {змін_однієї}; (було → стало): {dict(одна.most_common())}")
св = json.load(open("аудит/перевірка/річ_колір_межі_сім_ї_20261105/мірило.json"))["свотчі"]
print("свотчі 40 (номер, hex, слово, блок, вердикт ДО → ПІСЛЯ), змінені:")
for н, с in enumerate(св, 1):
    до, після = Д.сім_ї_кольору(с["lab"]), Т.сім_ї_кольору(с["lab"])
    if до != після:
        print(f"  №{н} {с['hex']} «{с['слово']}» блок {с['блок']}: {ім(до)} → "
              + " · ".join(f"{к} {в:.2f}" for к, в in після))
