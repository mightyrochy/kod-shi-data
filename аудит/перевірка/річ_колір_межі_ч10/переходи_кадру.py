"""Ч10: переходи вердиктів `колір_річ.відношення` й `та_сама_сім_я` для 96 речей зі зміненим вікном кадру.

Запуск із джерела/: python3 ../аудит/перевірка/річ_колір_межі_ч10/переходи_кадру.py <кадр_до.json.gz> <кадр_після.json.gz>
<відношення_до.json> <відношення_після.json> (два останні — вихід `відношення_кадру.py` на дереві ДО і ПІСЛЯ).
Група «а» — дуга ДО не тримала кінців дуги ПІСЛЯ (ціле округлення відрізало тон кадру), «б» — тримала (клітинка ширша)."""
import collections, gzip, json, sys
sys.path.insert(0, ".")
import колір_тон as T

до, пс = (json.load(gzip.open(ш)) for ш in sys.argv[1:3])
Д = {r[0]: r[1] for r in до["вікна_речей"]}
П = {r[0]: r[1] for r in пс["вікна_речей"]}
А, Б = "а: дуга ДО відрізала тон кадру", "б: дуга ДО ширша за тон кадру (клітинка)"
група = {}
for і in Д:
    if Д[і] == П[і]:
        continue
    дд, дп = Д[і][4], П[і][4]
    група[і] = Б if T.in_arc(дп[0], дд) and T.in_arc(дп[1], дд) else А
print("речей зі зміненим вікном:", dict(collections.Counter(група.values())))
від_до, від_пс = (json.load(open(ш)) for ш in sys.argv[3:5])
пари, переходи = collections.Counter(), collections.Counter()
for (а, б, вд, сд), (а2, б2, вп, сп) in zip(від_до, від_пс):
    assert (а, б) == (а2, б2)
    г = група[а]
    змін = вд != вп or сд != сп
    пари["%s / %s" % (г, змін)] += 1
    for к in вд:
        if вд[к] != вп[к]:
            переходи[(г[0], "%s: %s → %s" % (к, вд[к], вп[к]))] += 1
    if сд != сп:
        переходи[(г[0], "та_сама_сім_я: %s → %s" % (сд, сп))] += 1
print("пар (група, вердикт змінився):", dict(sorted(пари.items())))
for (г, т), н in sorted(переходи.items()):
    print("%5d  %s  %s" % (н, г, т))
