"""Ч10 Річ-колір-межі: виходи змінених функцій на тих самих входах — для дерева ДО і ПІСЛЯ.

Запуск: python3 повтор.py <тека джерела дерева> <вихід.json>. Входи: 9 535 точок каталогу з виміром
(`../річ_колір_межі_тон_20261105/каталог_точки.json.gz`), вікна `verify.ВЖИТОК`/`ЛЕКСИКОН`, клітинки
`міст_основи.ґратка_основ`, сітки й випадкові числа зі сталим зерном. Вихід — по функції: число входів,
SHA-256 виходів і самі виходи (для пошуку розбіжностей). Порівняння — `порівняти.py`."""
import gzip, hashlib, json, os, random, sys, warnings
from pathlib import Path

warnings.filterwarnings("ignore")
ТУТ = Path(__file__).resolve().parent
тека, вихід = Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve()
sys.path.insert(0, str(тека)); os.chdir(тека)
import verify as V, міст_основи as МО, surface as S, фід_добір as ФД, фід_збагачення as ФЗ
import фід_кадр_колір as ФКК, пакет_моделі as ПМ, суд_від_моделі as СВ, colorspace as cs
import колір_простір_перетворення as П

точки = [(і, tuple(lab)) for і, lab, *_ in json.load(gzip.open(ТУТ.parent / "річ_колір_межі_тон_20261105"
                                                                  / "каталог_точки.json.gz")) if lab]
вікна = sorted({(т, ім): в for т, tab in (("ВЖИТОК", V.ВЖИТОК), ("ЛЕКСИКОН", V.ЛЕКСИКОН))
                for ім, в in tab.items()}.items())
слова = sorted(V.ЛЕКСИКОН)
р = random.Random(10)
дробові = [(round(р.uniform(0, 360), 3), round(р.uniform(0, 360), 3)) for _ in range(300)]
дуги = [в[4] for _, в in вікна if в[4]] + дробові
out = {}

def запис(ім, xs):
    out[ім] = dict(n=len(xs), sha=hashlib.sha256(json.dumps(xs, ensure_ascii=False).encode()).hexdigest(), xs=xs)

def q_з(в, a=None, b=None, нейтраль=False):
    return dict(L_min=в[0], L_max=в[1], C_min=в[2], C_max=в[3], h_from=a, h_to=b, нейтраль=нейтраль)

# surface.слово_з_lab (відстань до дуги) і surface._одне_світло (Δh тіні)
запис("surface.слово_з_lab", [S.слово_з_lab(lab) for _, lab in точки])
пари = [(точки[i][1], точки[(i * 7919 + 13) % len(точки)][1]) for i in range(len(точки))]
пари += [(П.lab_з_lch(L, C, h1), П.lab_з_lch(L - 10, C, h2)) for L in (40, 70) for C in (12, 40)
         for h1 in range(0, 360, 5) for h2 in range(0, 360, 5)]
запис("surface._одне_світло", [S._одне_світло(а, б) for а, б in пари])

# міст_основи: hex_lch і _вікно_плашки на клітинках ґратки (справжні виклики) і всіх словах
запис("міст_основи.hex_lch", [МО.hex_lch(L, C, h) for L in range(0, 101, 2) for C in range(0, 140, 4)
                               for h in range(0, 360, 3)] + [МО.hex_lch(р.uniform(0, 100), р.uniform(0, 150),
                                                                        р.uniform(0, 360)) for _ in range(50000)])
осн, _ = МО.ґратка_основ()
плашки = []
for ключ, (hx, назва) in sorted(осн.items()):
    L, C, h = cs.lch(cs.hx(hx))
    с = МО._PS.сім_я_тону(h)
    дуга = с[2] if с else None
    for ім in [назва] + слова:
        плашки.append([ключ, ім, МО._вікно_плашки(ключ, hx, дуга, ім)])
запис("міст_основи._вікно_плашки", плашки)

# фід_добір: частка_вікна, відстань_до_центру, відстань_до_вікна, Словник.describe
qs = [q_з(в, *(в[4] or (None, None))) for _, в in вікна]
qs += [q_з(вікна[0][1], a, b) for a, b in дробові[:60]]
qs += [q_з(в, нейтраль=True) for _, в in вікна[:20]]
запис("фід_добір.частка_вікна", [ФД.частка_вікна(в[:4] + (д,), q) for _, в in вікна[::3]
                                  for д in [в[4]] + дробові[:5] for q in qs[::4]])
підтоми = точки[::5]
запис("фід_добір.відстань_до_центру", [ФД.відстань_до_центру(lab, q) for _, lab in підтоми for q in qs[::6]])
запис("фід_добір.відстань_до_вікна", [ФД.відстань_до_вікна(lab, q) for _, lab in підтоми for q in qs[::6]])
сл = ФД.Словник({"сірий": dict(придатна=True, lab=[50, 0, 0]), "бордо": dict(придатна=True, lab=[30, 40, 15])})
запис("фід_добір.Словник.describe", [сл.describe(L, rel, h) for L in range(5, 100, 5)
                                     for rel in (0.1, 0.4, 0.9) for h in range(0, 360, 2)])

# фід_збагачення: до_вікна (усі слова) і центр_вікна (усі вікна й дробові дуги)
запис("фід_збагачення.до_вікна", [ФЗ.до_вікна(lab, ім) for _, lab in точки[::3] for ім in слова])
запис("фід_збагачення.центр_вікна", [ФЗ.центр_вікна(в) for _, в in вікна]
      + [ФЗ.центр_вікна((40, 60, 10, 30, д)) for д in дробові])

# пакет_моделі.нейтральний_тон, суд_від_моделі.у_вікнах і lab_з
запис("пакет_моделі.нейтральний_тон", [ПМ.нейтральний_тон(h, C, L) for h in [None] + list(range(0, 360, 3))
                                       for C in (None, 0, 3, 8, 15, 30) for L in (None, 20, 45, 70, 95)])
вп = [dict(L=(20, 80), C=(5, 60), сім_ї={"червона": [(340.0, 20.0)], "синя": [(220.0, 270.0)]}),
      dict(L=(30, 70), C=(10, 40), сім_ї={"зелена": [(120.0, 170.0)]})]
запис("суд_від_моделі.у_вікнах", [СВ.у_вікнах(в, L, C, h) for в in вп for L in range(10, 100, 10)
                                  for C in (2, 10, 30, 70) for h in range(0, 360, 5)])
запис("суд_від_моделі.lab_з", [list(СВ.lab_з(L, C, h)) for L in range(0, 101, 5) for C in range(0, 120, 7)
                               for h in range(0, 360, 3)])

# фід_кадр_колір.вікно_з_кадром: кожне вікно слова × точка кадру з каталогу (як `_вікно_свідка`)
кадри = [ФКК._вікно_свідка(None, lab) for _, lab in точки[::7]]
запис("фід_кадр_колір.вікно_з_кадром", [[ім, i, ФКК.вікно_з_кадром(в, к)] for ім, в in вікна
                                         for i, к in enumerate(кадри) if к and в[4] and к[4]])
вихід.write_text(json.dumps(out, ensure_ascii=False), encoding="utf-8")
print("\n".join("%-34s n=%-7d %s" % (к, в["n"], в["sha"][:16]) for к, в in out.items()))
