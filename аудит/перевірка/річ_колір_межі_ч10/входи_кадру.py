"""Ч10: справжні входи `фід_кадр_колір.вікно_з_кадром` зі збірки всього каталогу (`каталог_повний.xml`).

Запуск із джерела/: python3 ../аудит/перевірка/річ_колір_межі_ч10/входи_кадру.py <вихід.json.gz>. Обгортає функцію,
яку імпортує `фід_каталог`, записує вікно слова, вікно кадру й вихід цього дерева; для речей із кадром іншого
кольору — id, вікно, сім'ю, нейтраль і гучність меж (`колір_річ`). Каталог — повний, без нових фото (ліміт 0)."""
import gzip, json, sys, warnings
warnings.filterwarnings("ignore")
sys.path.insert(0, ".")
import фід_каталог as ФК

входи, справжня = [], ФК.вікно_з_кадром

def обгортка(вікно, вікно_кадру):
    в = справжня(вікно, вікно_кадру)
    входи.append([вікно, вікно_кадру, в])
    return в

ФК.вікно_з_кадром = обгортка
каталог = ФК.прочитати_каталог(ФК.каталог_на_диску("каталог_повний.xml"), 0)   # без фото — як `проби/колір_тон_каталог.py`
записи = каталог["каталог"]
import колір_річ as КР
з_вікном = [[r.get("id"), r.get("вікно"), КР.сім_я_меж(r), КР.нейтраль_меж(r), КР.гучність_меж(r)]
            for r in записи if isinstance(r, dict) and r.get("кадр_кольору") and r.get("вікно") is not None]
with gzip.open(sys.argv[1], "wt", encoding="utf-8") as вихід:
    json.dump(dict(речей=len(записи), викликів=len(входи), входи=входи, вікна_речей=з_вікном), вихід,
              ensure_ascii=False)
print("речей %d, викликів вікно_з_кадром %d, речей з кадром іншого кольору й вікном %d" % (len(записи), len(входи), len(з_вікном)))
