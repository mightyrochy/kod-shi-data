"""Ч10: справжні входи `фід_кадр_колір.вікно_з_кадром` зі збірки всього каталогу (`каталог_повний.xml`).

Запуск із джерела/: python3 ../аудит/перевірка/річ_колір_межі_ч10/входи_кадру.py <вихід.json.gz>. Обгортає функцію,
яку імпортує `фід_каталог`, записує id речі, вікно слова, вікно кадру й вихід цього дерева; каталог — повний."""
import gzip, json, sys, warnings
warnings.filterwarnings("ignore")
sys.path.insert(0, ".")
import фід_каталог as ФК

входи, справжня = [], ФК.вікно_з_кадром

def обгортка(вікно, вікно_кадру):
    в = справжня(вікно, вікно_кадру)
    входи.append([вікно, вікно_кадру, в])
    return в

ФК.вікно_з_кадром = обгортка
каталог = ФК.прочитати_каталог(ФК.каталог_на_диску())
записи = каталог["каталог"]
з_вікном = [[r.get("id"), r.get("вікно")] for r in записи if isinstance(r, dict) and r.get("вікно") is not None]
json.dump(dict(речей=len(записи), викликів=len(входи), входи=входи, вікна_речей=з_вікном),
          gzip.open(sys.argv[1], "wt", encoding="utf-8"), ensure_ascii=False)
print("речей %d, викликів вікно_з_кадром %d, речей з полем «вікно» %d" % (len(записи), len(входи), len(з_вікном)))
