"""Звіряє геометрію й орієнтацію зшивання незалежним обходом країв.

Власна перевірка виконавця, не незалежне приймання таблиці сімей.
Запуск із кореня: python аудит/перевірка/річ_колір_межі_зшивання.py
"""
from collections import Counter, defaultdict
import copy
import importlib.util
import json
import math
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch


КОРІНЬ = Path(__file__).resolve().parents[2]
ШЛЯХ = КОРІНЬ / "джерела/лабораторія/колір_сім_ї_зшивання.py"
СПЕЦИФІКАЦІЯ = importlib.util.spec_from_file_location("зшивання", ШЛЯХ)
МОДУЛЬ = importlib.util.module_from_spec(СПЕЦИФІКАЦІЯ)
СПЕЦИФІКАЦІЯ.loader.exec_module(МОДУЛЬ)


def перехресний(a, b):
    """Дає напрямок обходу t=n×m з нормалі площини та зовнішньої нормалі краю."""
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2],
            a[0] * b[1] - a[1] * b[0])


class ПеревіркаЗшивання(unittest.TestCase):
    """Перевіряє всі вихідні грані, шов, промені, Т-стики й орієнтацію."""

    @classmethod
    def setUpClass(клас):
        """Читає збережений артефакт і первинні прямокутні поверхні."""
        клас.комплекс = json.loads(МОДУЛЬ.ВИХІД.read_text(encoding="utf-8"))
        клас.джерело = json.loads(МОДУЛЬ.ВХІД.read_text(encoding="utf-8"))

    def test_відтворення_та_походження(self):
        """Повторне породження точне в LF/CRLF; підміна джерела відхиляється."""
        вихід = МОДУЛЬ.породити()
        текст = МОДУЛЬ.серіалізувати(вихід)
        self.assertEqual(текст.encode(), МОДУЛЬ.ВИХІД.read_text(encoding="utf-8").encode())
        with tempfile.TemporaryDirectory() as тека:
            файл = Path(тека) / "підміна.json"
            підміна = copy.deepcopy(self.джерело)
            підміна["межі"][0]["сім_ї"].reverse()
            файл.write_text(json.dumps(підміна), encoding="utf-8")
            with patch.object(МОДУЛЬ, "ВХІД", файл), self.assertRaises(ValueError):
                МОДУЛЬ.породити()
            файл.write_bytes(текст.replace("\n", "\r\n").encode())
            прогін = subprocess.run([sys.executable, str(ШЛЯХ), "--вихід", str(файл)],
                                     stdout=subprocess.DEVNULL, stderr=subprocess.PIPE,
                                     encoding="utf-8")
            self.assertEqual(прогін.returncode, 0, прогін.stderr)

    def test_повні_краї_та_орієнтація(self):
        """Кожний вихідний край покритий рівно раз без прогалин і перекриття."""
        ребра = self.комплекс["ребра"]
        перевірено = 0
        for грань, контур in zip(self.джерело["межі"], self.комплекс["контури"]):
            вісь = "HVC".index(грань["вісь"])
            нормаль = [int(i == вісь) for i in range(3)]
            інші = [i for i in range(3) if i != вісь]
            зіставлено = []
            for фіксована in інші:
                змінна = next(i for i in інші if i != фіксована)
                межі = грань["інтервали"][інші.index(змінна)]
                for бік, край in enumerate(грань["інтервали"][інші.index(фіксована)]):
                    if край == "+inf":
                        continue
                    зовнішня = [0, 0, 0]
                    зовнішня[фіксована] = -1 if бік == 0 else 1
                    напрямок = перехресний(нормаль, зовнішня)[змінна]
                    точка = {вісь: грань["координата"], фіксована: край}
                    if точка.get(0) == 101:
                        точка[0] = 1
                    фіксовані = [точка[i] for i in range(3) if i != змінна]
                    частини = []
                    for посилання in контур:
                        номер, знак = abs(посилання) - 1, 1 if посилання > 0 else -1
                        ребро = ребра[номер]
                        if (ребро["вісь"] == "HVC"[змінна] and
                                ребро["фіксовані"] == фіксовані and знак == напрямок):
                            частини.append(ребро["інтервал"])
                            зіставлено.append(посилання)
                    self.assertTrue(частини)
                    частини.sort(key=lambda x: x[0])
                    self.assertEqual(частини[0][0], межі[0])
                    self.assertEqual(частини[-1][1], межі[1])
                    for a, b in zip(частини, частини[1:]):
                        self.assertEqual(a[1], b[0])
                    перевірено += 1
            self.assertEqual(Counter(зіставлено), Counter(контур))
        self.assertEqual(len(self.комплекс["контури"]), len(self.джерело["межі"]))
        print(f"Повністю покритих орієнтованих країв: {перевірено}")

    def test_ребра_вершини_зворотні_зв_язки(self):
        """Координати й інцидентність унікальні; зворотні списки збігаються."""
        точки = self.комплекс["вершини"]
        self.assertEqual(len(точки), len({tuple(x) for x in точки}))
        self.assertTrue(all(1 <= H < 101 and all(map(math.isfinite, (H, V, C)))
                            for H, V, C in точки))
        зворотні = defaultdict(list)
        for грань, контур in enumerate(self.комплекс["контури"]):
            for посилання in контур:
                зворотні[abs(посилання) - 1].append((1 if посилання > 0 else -1) * (грань + 1))
        ключі = []
        for i, ребро in enumerate(self.комплекс["ребра"]):
            self.assertEqual(зворотні[i], ребро["грані"])
            ключі.append((ребро["вісь"], tuple(ребро["фіксовані"]), tuple(ребро["інтервал"])))
            вісь = "HVC".index(ребро["вісь"])
            for край, номер in zip(ребро["інтервал"], ребро["вершини"]):
                if край == "+inf":
                    self.assertIsNone(номер)
                else:
                    очікувана = list(ребро["фіксовані"])
                    очікувана.insert(вісь, край)
                    if очікувана[0] == 101:
                        очікувана[0] = 1
                    self.assertEqual(точки[номер], очікувана)
        self.assertEqual(len(ключі), len(set(ключі)))

    def test_замкненість_із_боків_джерела(self):
        """Всі сім'ї скорочують ребра; знак оболонки узгоджений із боком джерела."""
        особливі = []
        for код in self.джерело["сім_ї"]:
            очікується = [знак * (i + 1) for i, грань in enumerate(self.джерело["межі"])
                         for знак, бік in ((1, 0), (-1, 1)) if грань["сім_ї"][бік] == код]
            self.assertEqual(self.комплекс["оболонки"][код], очікується)
            for i, ребро in enumerate(self.комплекс["ребра"]):
                знаки = []
                for f in ребро["грані"]:
                    сім_ї = self.джерело["межі"][abs(f) - 1]["сім_ї"]
                    if код in сім_ї:
                        знаки.append((1 if f > 0 else -1) * (1 if сім_ї[0] == код else -1))
                self.assertEqual(sum(знаки), 0)
                if знаки and len(знаки) != 2:
                    особливі.append({"сім_я": код, "ребро": i, "кратність": len(знаки)})
        self.assertEqual(особливі, self.комплекс["підсумок"]["недвобічні_стики"])
        МОДУЛЬ.перевірити(self.комплекс)
        print(f"Сімей із нульовою межею: {len(self.джерело['сім_ї'])}; особливі стики: {особливі}")

    def test_повний_оберт_та_промені(self):
        """Синтетичний повний H не схлопується; нескінченність не дає кришки."""
        вхід = {"сім_ї": ["a"], "межі": [
            {"вісь": "V", "координата": 0, "інтервали": [[1, 101], [0, "+inf"]],
             "сім_ї": [None, "a"]},
            {"вісь": "V", "координата": 10, "інтервали": [[1, 101], [0, "+inf"]],
             "сім_ї": ["a", None]},
            {"вісь": "C", "координата": 0, "інтервали": [[1, 101], [0, 10]],
             "сім_ї": [None, "a"]}]}
        комплекс = МОДУЛЬ.побудувати(вхід)
        підсумок = МОДУЛЬ.перевірити(комплекс)
        self.assertEqual(підсумок["променів"], 2)
        оберти = [e for e in комплекс["ребра"] if e["вісь"] == "H"]
        self.assertEqual(len(оберти), 2)
        self.assertTrue(all(e["інтервал"] == [1, 101] and
                            e["вершини"][0] == e["вершини"][1] for e in оберти))

    def test_частковий_збіг_Т_стик(self):
        """Поділ однієї площини створює спільний край із довгим сусіднім краєм."""
        вхід = {"сім_ї": ["a"], "межі": [
            {"вісь": "V", "координата": 5, "інтервали": [[1, 101], [0, 4]],
             "сім_ї": ["a", None]},
            {"вісь": "C", "координата": 4, "інтервали": [[1, 30], [0, 5]],
             "сім_ї": ["a", None]},
            {"вісь": "C", "координата": 4, "інтервали": [[30, 101], [0, 5]],
             "сім_ї": ["a", None]}]}
        комплекс = МОДУЛЬ.побудувати(вхід)
        спільні = [e for e in комплекс["ребра"] if e["вісь"] == "H" and
                   e["фіксовані"] == [5, 4]]
        self.assertEqual([e["інтервал"] for e in спільні], [[1, 30], [30, 101]])
        self.assertTrue(all(len(e["грані"]) == 2 for e in спільні))

    def test_втрата_та_переворот_відхиляються(self):
        """Контроль замикання бачить втрату ребра й переворот зовнішньої грані."""
        зламане = copy.deepcopy(self.комплекс)
        зламане["контури"][0].pop()
        with self.assertRaisesRegex(ValueError, "контур"):
            МОДУЛЬ.перевірити(зламане)
        зламане = copy.deepcopy(self.комплекс)
        код = next(iter(зламане["оболонки"]))
        зламане["оболонки"][код][0] *= -1
        with self.assertRaisesRegex(ValueError, "сім'ї"):
            МОДУЛЬ.перевірити(зламане)


if __name__ == "__main__":
    unittest.main(verbosity=2)
