"""Звіряє нові прямі жнива та наступні продовження обходу на одному журналі."""
import json
import tempfile
from незалежна import Стенд, річ


def main():
    """Перевіряє, що нова адреса отримана через API, а обхід після цього не робить HTTP."""
    for сім in ("woo", "shopify"):
        with tempfile.TemporaryDirectory(prefix="review-2069-sequence-") as журнал:
            с = Стенд(журнал, сім)
            с.прогін({1: [річ(1), річ(2)], 2: [річ(3)], 3: []})
            нові = с.прогін({1: [річ(1), річ(2)], 2: [річ(3), річ(4)], 3: []})
            повтори = [с.прогін({}, через_обхід=True) for _ in range(2)]
            факти = с.факти()
            assert нові == [1, 2, 3] and повтори == [[], []]
            assert len(факти["адреси"]) == 4 and факти["записів"] == 4
            assert факти["кінець"] and факти["сума_збігається"]
            print(json.dumps(dict(сімейство=сім, нові_HTTP=нові, повтори_HTTP=повтори,
                                  **факти), ensure_ascii=False))
    print("Послідовність: 2/2, усі міряла виконано")


if __name__ == "__main__":
    main()
