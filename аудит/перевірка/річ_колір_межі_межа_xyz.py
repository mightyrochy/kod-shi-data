ЧАСТКИ = [i / 40 for i in range(41)]
# Смуга біля кривої за вагою: коефіцієнти форм записано 12 значущими цифрами.
БІЛЯ = 1e-9
ЛІЧБА = {}


def число(x):
    """Читає «+inf» збереженого виходу."""
    return math.inf if x == "+inf" else x


def у_частині(частина, x):
    """Належність координати частині [від, до] із замкненістю кінців."""
    від, до, зв, зд, _ = частина
    від, до = число(від), число(до)
    return від < x < до or (x == від and зв) or (x == до and зд)


def у_області(область, t):
    """Читає збережене об'єднання інтервалів із замкненістю кінців."""
    return any(x["від"] < t < x["до"] or (t == x["від"] and x["замкнено"][0])
               or (t == x["до"] and x["замкнено"][1]) for x in область)


class Опис:
    """Читач збереженої кривої клітинки: змінні p і w, крива та стан точки."""

    def __init__(self, бібліотека, запис):
        self.бібліотека, self.запис = бібліотека, запис

    def змінна_p(self, x):
        p = self.запис["p"]
        if p["вісь"] == "H":
            return x - p["від_частини"]
        if p["змінна"] == "смуга цілого V":
            return 0.0
        return МОДУЛЬ.вага_V(self.бібліотека, p["від_частини"], x)

    def вага_w(self, x):
        w = self.запис["w"]
        if w["вісь"] == "C":
            return (x - w["члени"][0]) / 2
        return МОДУЛЬ.вага_V(self.бібліотека, w["члени"][0], x)

    def координата_w(self, вага):
        """Координата C чи V кривої з ваги."""
        w = self.запис["w"]
        if w["вісь"] == "C":
            return w["члени"][0] + 2 * вага
        return МОДУЛЬ.координата(lambda x: self.вага_w(x), w["члени"][0], w["члени"][1], вага)

    def частина(self, x):
        for p, q, s in self.запис["частини"]:
            if p <= x <= q:
                return s
        raise AssertionError(x)

    def крива(self, назва, x):
        return МОДУЛЬ.вага_кривої(self.запис["обмеження"][назва], self.змінна_p(x))

    def стан(self, x, y):
        """(визначено за описом, відстань ваги від кривої або None)."""
        s = self.частина(x)
        if s in ("+", "-"):
            return s == "+", None
        знак, назва = s.split()
        різниця = self.вага_w(y) - self.крива(назва, x)
        return (різниця <= 0) if знак == "≤" else (різниця >= 0), abs(різниця)


def клітинка(грань, осі, т):
    """Рядки й стовпці частин грані, що містять точку."""
    return ([i for i, ч in enumerate(грань["частини"][0]) if у_частині(ч, т[осі[0]])],
            [j for j, ч in enumerate(грань["частини"][1]) if у_частині(ч, т[осі[1]])])


def точка(запис, x, y, фіксована):
    """H/V/C з координат p, w і фіксованої осі."""
    результат = [0.0] * 3
    результат["HVC".index(фіксована[0])] = фіксована[1]
    результат["HVC".index(запис["p"]["вісь"])] = x
    результат["HVC".index(запис["w"]["вісь"])] = y
    return результат


class ПеревіркаМежі(unittest.TestCase):
    """Відтворення, облік клітинок «x», прямий метод, межа прямого методу, ребра."""

    @classmethod
    def setUpClass(клас):
        warnings.filterwarnings("ignore")
        клас.вихід = json.loads(МОДУЛЬ.ВИХІД.read_text(encoding="utf-8"))
        клас.області = json.loads(ГРАНІ.ВИХІД.read_text(encoding="utf-8"))["грані"]
        клас.комплекс = json.loads(РЕБРА.ВХІД.read_text(encoding="utf-8"))
        клас.ребра = json.loads(РЕБРА.ВИХІД.read_text(encoding="utf-8"))["ребра"]
        клас.тону = {x["ребро"]: x for x in json.loads(ТОН.ВИХІД.read_text(encoding="utf-8"))["ребра"]}
        клас.бібліотека = ОСНОВА.залежності()
        клас.перетворити = staticmethod(ОСНОВА.зробити_перетворення(клас.бібліотека))
        клас.за_клітинкою = {(x["грань"], *x["клітинка"]): x for x in клас.вихід["клітинки"]}

    def визначено(self, H, V, C):
        try:
            self.перетворити(H, V, C)
        except (AssertionError, ValueError) as помилка:
            self.assertIn("Непридатний XYZ", str(помилка), (H, V, C))
            return False
        return True

    def test_відтворення_та_підміна(self):
        """Повторне породження побайтове; підміна областей граней — відмова до породження.

        Області граней породжуються повністю один раз: той самий вихід дістають обидва виклики.
        """
        граней = ГРАНІ.породити()
        self.assertEqual(ГРАНІ.серіалізувати(граней), ГРАНІ.ВИХІД.read_text(encoding="utf-8"))
        with patch.object(ГРАНІ, "породити", lambda: граней):
            текст = МОДУЛЬ.серіалізувати(МОДУЛЬ.породити())
            self.assertEqual(текст.encode(), МОДУЛЬ.ВИХІД.read_bytes())
            with tempfile.TemporaryDirectory() as тека:
                підміна = Path(тека) / "грані.json"
                підміна.write_text(ГРАНІ.ВИХІД.read_text(encoding="utf-8").replace('"x"', '"+"', 1),
                                   encoding="utf-8")
                with patch.object(ГРАНІ, "ВИХІД", підміна), self.assertRaises(ValueError):
                    МОДУЛЬ.породити()

    def test_облік(self):
        """Рівно клітинки «x» областей граней; частини p суміжні, покривають частину, є межа."""
        очікувані = {(г["грань"], i, j) for г in self.області if not г.get("нейтраль")
                     for i, рядок in enumerate(г["стани"]) for j, s in enumerate(рядок) if s == "x"}
        self.assertEqual(set(self.за_клітинкою), очікувані)
        self.assertEqual(len(self.вихід["клітинки"]), len(очікувані))
        for запис in self.вихід["клітинки"]:
            грань = self.області[запис["грань"]]
            i, j = запис["клітинка"]
            частини = dict(zip(грань["осі"], (грань["частини"][0][i], грань["частини"][1][j])))
            p = запис["p"]
            self.assertEqual([p["від"], p["до"]], частини[p["вісь"]][:2])
            self.assertEqual(запис["частини"][0][0], p["від"])
            self.assertEqual(запис["частини"][-1][1], p["до"])
            for a, b in zip(запис["частини"], запис["частини"][1:]):
                self.assertEqual(a[1], b[0])
                self.assertNotEqual(a[2], b[2])
            стани = {s for *_, s in запис["частини"]}
            self.assertTrue(стани - {"+", "-"} or стани == {"+", "-"}, запис["клітинка"])
        ЛІЧБА["клітинок"] = len(очікувані)

    def test_прямим_методом(self):
        """40 випадкових точок кожної клітинки та 10 біля кривої — стан опису проти Colour."""
        генератор, лічба = random.Random(29), {"збіг": 0, "визначено": 0, "XYZ": 0,
                                                  "біля_кривої": 0, "розбіжностей": 0}
        for запис in self.вихід["клітинки"]:
            опис = Опис(self.бібліотека, запис)
            фіксована = self.області[запис["грань"]]["фіксована"]
            p, w = запис["p"], запис["w"]
            точки = [(генератор.uniform(p["від"], p["до"]), генератор.uniform(w["від"], w["до"]))
                     for _ in range(40)]
            for a, b, s in запис["частини"]:
                if s in ("+", "-"):
                    continue
                for _ in range(5):
                    x = генератор.uniform(a, b)
                    y = опис.координата_w(опис.крива(s.split()[1], x))
                    if w["від"] < y < w["до"]:
                        точки += [(x, y * (1 + 1e-6)), (x, y * (1 - 1e-6))]
            for x, y in точки:
                за_описом, відстань = опис.стан(x, y)
                прямо = self.визначено(*точка(запис, x, y, фіксована))
                if відстань is not None and відстань < БІЛЯ:
                    лічба["біля_кривої"] += 1
                    continue
                лічба["визначено" if прямо else "XYZ"] += 1
                if за_описом != прямо:
                    лічба["розбіжностей"] += 1
                    self.fail((запис["грань"], запис["клітинка"], x, y, відстань))
                лічба["збіг"] += 1
        ЛІЧБА["прямим_методом"] = лічба

    def test_крива_проти_межі_прямого_методу(self):
        """У 5 точках p кожної частини з кривою — межа Colour уздовж w бісекцією проти кривої."""
        генератор, найбільша, точок = random.Random(31), 0.0, 0
        for запис in self.вихід["клітинки"]:
            опис = Опис(self.бібліотека, запис)
            фіксована = self.області[запис["грань"]]["фіксована"]
            w = запис["w"]
            for a, b, s in запис["частини"]:
                if s in ("+", "-"):
                    continue
                знак, назва = s.split()
                for x in [генератор.uniform(a, b) for _ in range(5)]:
                    y = опис.координата_w(опис.крива(назва, x))
                    низ, верх = w["від"], число(w["до"])
                    if not низ < y < верх:
                        continue
                    всередині, назовні = (низ, верх) if знак == "≤" else (верх, низ)
                    if not self.визначено(*точка(запис, x, всередині, фіксована)):
                        всередині = (всередині + y) / 2
                    межа = РЕБРА.межа(lambda t: self.визначено(*точка(запис, x, t, фіксована)),
                                      всередині, назовні)
                    найбільша = max(найбільша, abs(межа - y))
                    точок += 1
        self.assertLess(найбільша, 1e-8)
        ЛІЧБА["межа_прямого_методу"] = {"точок": точок, "найбільша_різниця": найбільша}

    def test_узгодження_з_ребрами(self):
        """Точки ребер у клітинках «x», не звірені областями граней, — за кривою проти області ребра."""
        перевірено, біля = 0, 0
        найбільша = 0.0
        for номер, ребро in enumerate(self.комплекс["ребра"]):
            запис = self.тону.get(номер) or self.ребра[номер]
            if запис["клас"] in ("нейтральна точка", "нейтральний відрізок"):
                continue
            вісь = "HVC".index(ребро["вісь"])
            низ, верх = (ЗШИВАННЯ.число(x) for x in ребро["інтервал"])
            верх_проб = min(верх, низ + 1000)
            точки = {низ + (верх_проб - низ) * t for t in ЧАСТКИ}
            for x in запис.get("область", []):
                for кінець in (x["від"], x["до"]):
                    точки |= {кінець, math.nextafter(кінець, math.inf), math.nextafter(кінець, -math.inf)}
            for посилання in ребро["грані"]:
                грань = self.області[ЗШИВАННЯ.розпакувати(посилання)[0]]
                if грань.get("нейтраль") or "x" not in "".join(грань["стани"]):
                    continue
                осі = ["HVC".index(x) for x in грань["осі"]]
                for t in sorted(x for x in точки if низ <= x <= верх_проб and not (вісь == 2 and x == 0)):
                    т = list(ребро["фіксовані"])
                    т.insert(вісь, t)
                    рядки, стовпці = клітинка(грань, осі, т)
                    # H=1 і H=101 ототожнено зшиванням.
                    if (len(рядки) != 1 or len(стовпці) != 1) and т[0] in (1.0, 101.0):
                        т[0] = 102.0 - т[0]
                        рядки, стовпці = клітинка(грань, осі, т)
                    self.assertTrue(len(рядки) == 1 and len(стовпці) == 1, (номер, грань["грань"], т))
                    if грань["стани"][рядки[0]][стовпці[0]] != "x":
                        continue
                    опис = Опис(self.бібліотека, self.за_клітинкою[(грань["грань"], рядки[0], стовпці[0])])
                    p, w = опис.запис["p"]["вісь"], опис.запис["w"]["вісь"]
                    за_описом, відстань = опис.стан(т["HVC".index(p)], т["HVC".index(w)])
                    у_ребрі = у_області(запис["область"], t)
                    if відстань is not None and відстань < БІЛЯ:
                        біля += 1
                        if за_описом != у_ребрі:
                            найбільша = max(найбільша, відстань)
                        continue
                    self.assertEqual(за_описом, у_ребрі, (номер, грань["грань"], т))
                    перевірено += 1
        ЛІЧБА["узгодження"] = {"перевірено": перевірено, "біля_кривої": біля,
                               "розбіжність_біля_кривої": найбільша}
        self.assertGreater(перевірено, 0)

    def test_межі_XYZ_ребер_на_кривій(self):
        """Кожна межа XYZ області ребра в прилеглій грані — точка кривої її клітинки «x»."""
        меж, точок, найбільша = 0, 0, 0.0
        for номер, запис in enumerate(self.ребра):
            ребро = self.комплекс["ребра"][номер]
            for інтервал in запис.get("область", []):
                for кінець, мітка in zip((інтервал["від"], інтервал["до"]), інтервал["межі"]):
                    if мітка != "XYZ":
                        continue
                    меж += 1
                    т = list(ребро["фіксовані"])
                    т.insert("HVC".index(ребро["вісь"]), кінець)
                    for посилання in ребро["грані"]:
                        грань = self.області[ЗШИВАННЯ.розпакувати(посилання)[0]]
                        осі = ["HVC".index(x) for x in грань["осі"]]
                        рядки, стовпці = клітинка(грань, осі, т)
                        self.assertEqual(грань["стани"][рядки[0]][стовпці[0]], "x", (номер, т))
                        опис = Опис(self.бібліотека, self.за_клітинкою[(грань["грань"], рядки[0], стовпці[0])])
                        p, w = опис.запис["p"]["вісь"], опис.запис["w"]["вісь"]
                        self.assertEqual(w, ребро["вісь"], (номер, грань["грань"]))
                        s = опис.частина(т["HVC".index(p)])
                        self.assertIn(s.split()[0], ("≤", "≥"), (номер, грань["грань"]))
                        y = опис.координата_w(опис.крива(s.split()[1], т["HVC".index(p)]))
                        найбільша = max(найбільша, abs(y - кінець))
                        точок += 1
        self.assertEqual(меж, 13)
        self.assertLess(найбільша, 1e-8)
        ЛІЧБА["межі_XYZ_ребер"] = {"меж": меж, "точок_у_гранях": точок, "найбільша_різниця": найбільша}

    def test_синтетичні_форми(self):
        """Лінійна форма з коренем 0.25 і стала додатна — частини й стан обмеження."""
        частини = МОДУЛЬ.знаки_на_частині((-1.0, 4.0, []), lambda x: x, 0.0, 1.0)
        self.assertEqual([(a, s) for a, _, s in частини], [(0.0, -1), (0.25, 1)])
        self.assertEqual(МОДУЛЬ.знаки_на_частині((2.0, 0.0, []), lambda x: x, 0.0, 1.0), [(0.0, 1.0, 1)])
        self.assertEqual([МОДУЛЬ.стан_обмеження(x) for x in ([1, -1], [-1, 1], [1, 1], [-1])],
                         ["≤", "≥", "+", "-"])
        запис = {"G": [МОДУЛЬ.форма_запис((1.0, 0.0, [])), МОДУЛЬ.форма_запис((-3.0, 0.0, []))]}
        self.assertEqual(МОДУЛЬ.вага_кривої(запис, 0.5), 0.25)


