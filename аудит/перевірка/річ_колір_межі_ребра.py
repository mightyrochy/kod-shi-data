"""Звіряє області ребер зшивання прямим методом, без лінійної моделі ребер.

Власна перевірка виконавця, не незалежне приймання сімей.
Запуск із кореня: python аудит/перевірка/річ_колір_межі_ребра.py
"""
import copy
import importlib.util
import json
import math
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch
import warnings


КОРІНЬ = Path(__file__).resolve().parents[2]
ШЛЯХ = КОРІНЬ / "джерела/лабораторія/колір_сім_ї_ребра.py"
СПЕЦИФІКАЦІЯ = importlib.util.spec_from_file_location("ребра", ШЛЯХ)
МОДУЛЬ = importlib.util.module_from_spec(СПЕЦИФІКАЦІЯ)
СПЕЦИФІКАЦІЯ.loader.exec_module(МОДУЛЬ)
ОСНОВА, СКІНЧЕННІ = МОДУЛЬ.ОСНОВА, МОДУЛЬ.СКІНЧЕННІ
ЧАСТКИ = (0, 0.03, 0.1, 0.25, 0.4, 0.5, 0.6, 0.75, 0.9, 0.97, 1)
ЛІЧБА = {}


def точка(вісь, фіксовані, t):
    """Розгортає параметр ребра в H/V/C."""
    точка = list(фіксовані)
    точка.insert("HVC".index(вісь), t)
    return tuple(точка)


def прямо(перетворити, H, V, C):
    """Відповідь попередніх методів: визначено чи ні, з причиною відмови."""
    if not СКІНЧЕННІ.визначено_V(V):
        return False, "V"
    try:
        перетворити(H, V, C)
    except (AssertionError, ValueError) as помилка:
        return False, "XYZ" if "Непридатний XYZ" in str(помилка) else "дані"
    return True, None


def у_області(область, t):
    """Читає збережене об'єднання інтервалів із замкненістю кінців."""
    for x in область:
        if (x["від"] < t < x["до"] or (t == x["від"] and x["замкнено"][0])
                or (t == x["до"] and x["замкнено"][1])):
            return True
    return False


class ПеревіркаРебер(unittest.TestCase):
    """Перевіряє відтворення, нейтраль, області, межі й узгодженість із вершинами."""

    @classmethod
    def setUpClass(клас):
        """Читає збережений вихід, зшивання та прямий метод попередніх кроків."""
        warnings.filterwarnings("ignore")
        клас.вихід = json.loads(МОДУЛЬ.ВИХІД.read_text(encoding="utf-8"))
        клас.комплекс = json.loads(МОДУЛЬ.ВХІД.read_text(encoding="utf-8"))
        клас.бібліотека = ОСНОВА.залежності()
        клас.перетворити = staticmethod(ОСНОВА.зробити_перетворення(клас.бібліотека))
        клас.нейтраль = staticmethod(МОДУЛЬ.НЕЙТРАЛЬ.зробити_перетворення(клас.бібліотека))

    def хроматичні(self):
        """Пари (ребро зшивання, запис області) класів C і V."""
        for запис in self.вихід["ребра"]:
            if запис["клас"] in ("C", "V"):
                yield self.комплекс["ребра"][запис["ребро"]], запис

    def test_відтворення_та_підміна(self):
        """Повторне породження побайтове, CRLF-копія звіряється; підміна зшивання — відмова."""
        текст = МОДУЛЬ.серіалізувати(МОДУЛЬ.породити())
        self.assertEqual(текст.encode(), МОДУЛЬ.ВИХІД.read_bytes())
        with tempfile.TemporaryDirectory() as тека:
            файл = Path(тека) / "копія.json"
            файл.write_bytes(текст.replace("\n", "\r\n").encode())
            прогін = subprocess.run([sys.executable, "-W", "ignore", str(ШЛЯХ), "--вихід", str(файл)],
                                     stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, encoding="utf-8")
            self.assertEqual(прогін.returncode, 0, прогін.stderr)
            підміна = copy.deepcopy(self.комплекс)
            підміна["ребра"][0]["інтервал"][1] += 1
            файл.write_text(json.dumps(підміна), encoding="utf-8")
            with patch.object(МОДУЛЬ, "ВХІД", файл), self.assertRaises(ValueError):
                МОДУЛЬ.породити()

    def test_облік_класів_за_геометрією(self):
        """Кожне з 1 127 ребер має рівно один клас, обраний із його координат."""
        очікувані = []
        for ребро in self.комплекс["ребра"]:
            вісь, (p, q) = ребро["вісь"], ребро["фіксовані"]
            V = {"H": p, "V": None, "C": q}[вісь]
            C = {"H": q, "V": q, "C": None}[вісь]
            if C == 0:
                очікувані.append("нейтральна точка" if вісь == "H" else "нейтральний відрізок")
            elif V in (0, 10):
                очікувані.append("кінець V")
            else:
                очікувані.append("відкладено" if вісь == "H" else вісь)
        self.assertEqual([x["клас"] for x in self.вихід["ребра"]], очікувані)
        self.assertEqual([x["ребро"] for x in self.вихід["ребра"]], list(range(len(очікувані))))

    def test_нейтраль_і_згортання(self):
        """C=0 вершини — образ нейтралі за V; H-ребра — одна точка; вироджується лише C=0-грань."""
        нейтральні_V = self.вихід["нейтральні_V"]
        for x, вершина in zip(self.комплекс["вершини"], self.вихід["вершини"]):
            if x[2] == 0:
                lab, θLC = self.нейтраль(x[1])
                self.assertEqual(вершина["Lab"], ОСНОВА.округлити(list(lab)))
                self.assertIsNone(вершина["θLC"][0])
        for ребро, запис in zip(self.комплекс["ребра"], self.вихід["ребра"]):
            if запис["клас"] == "нейтральна точка":
                кінці = {self.комплекс["вершини"][i][1] for i in ребро["вершини"]}
                self.assertEqual({нейтральні_V[запис["нейтраль"]]}, кінці)
            if запис["клас"] == "нейтральний відрізок":
                self.assertEqual([нейтральні_V[i] for i in запис["нейтраль"]], запис["V"])
        межі = json.loads(ОСНОВА.ВХІД.read_text(encoding="utf-8"))["межі"]
        нульові = self.вихід["підсумок"]["вироджені_контури"]
        self.assertEqual(нульові, [i for i, g in enumerate(межі)
                                   if g["вісь"] == "C" and g["координата"] == 0])
        # Хроматичні ребра C від 0 є лише на V=0/10: їхній початок — кінець нейтралі.
        від_нуля = [(ребро, запис) for ребро, запис in zip(self.комплекс["ребра"], self.вихід["ребра"])
                    if ребро["вісь"] == "C" and ребро["інтервал"][0] == 0]
        for ребро, запис in від_нуля:
            self.assertEqual(запис["клас"], "кінець V")
            self.assertEqual(нейтральні_V[запис["нейтраль"]], ребро["фіксовані"][1])
        ЛІЧБА["C_від_нуля"] = len(від_нуля)


    def test_область_проти_прямого_методу(self):
        """Внутрішні проби всіх ребер C/V збігаються з прямим методом, без винятків."""
        проби = прийнято = 0
        for ребро, запис in self.хроматичні():
            низ, верх = (МОДУЛЬ.ЗШИВАННЯ.число(x) for x in ребро["інтервал"])
            параметри = ([низ + (верх - низ) * t for t in ЧАСТКИ] if math.isfinite(верх)
                         else [низ + d for d in (0, 0.5, 1, 3, 7, 12, 20, 35, 49, 50.5, 80, 1e3)])
            for t in параметри:
                if запис["клас"] == "C" and t == 0:
                    continue
                H, V, C = точка(ребро["вісь"], ребро["фіксовані"], t)
                if not 0 < V < 10:
                    continue
                визначено, _ = прямо(self.перетворити, H, V, C)
                self.assertEqual(визначено, у_області(запис["область"], t), (ребро, t))
                проби += 1
                прийнято += визначено
        ЛІЧБА["внутрішні"] = (проби, прийнято)

    def test_межі_області_та_причини(self):
        """Кожна межа: точна для даних і смуг, ±1e-9 для XYZ; причина зовні збігається."""
        лічба = {}
        for ребро, запис in self.хроматичні():
            for інтервал in запис["область"]:
                for бік, напрям in ((0, -1), (1, 1)):
                    e, причина = інтервал["до" if бік else "від"], інтервал["межі"][бік]
                    if причина in ("край ребра", "нейтраль"):
                        continue
                    if причина == "XYZ":
                        крок = 1e-9 * max(1, abs(e))
                        всередині, зовні = e - напрям * крок, e + напрям * крок
                    else:
                        всередині = e if інтервал["замкнено"][бік] else math.nextafter(e, -напрям * math.inf)
                        зовні = math.nextafter(e, напрям * math.inf) if інтервал["замкнено"][бік] else e
                    так, _ = прямо(self.перетворити, *точка(ребро["вісь"], ребро["фіксовані"], всередині))
                    ні, чому = прямо(self.перетворити, *точка(ребро["вісь"], ребро["фіксовані"], зовні))
                    self.assertTrue(так, (ребро, інтервал, бік))
                    self.assertFalse(ні, (ребро, інтервал, бік))
                    self.assertEqual(чому == "XYZ", причина == "XYZ", (ребро, інтервал, бік, чому))
                    лічба[причина] = лічба.get(причина, 0) + 1
        ЛІЧБА["межі"] = лічба

    def test_вершини_узгоджені_з_ребрами(self):
        """Визначена вершина лежить у замкненій області кожного свого ребра C/V, невизначена — ні."""
        перевірено = 0
        for ребро, запис in self.хроматичні():
            вісь = "HVC".index(ребро["вісь"])
            for номер in ребро["вершини"]:
                if номер is None:
                    continue
                вершина = self.вихід["вершини"][номер]
                if вершина["стан"] == "нейтраль":
                    self.assertEqual(запис["клас"], "C")
                    self.assertIn("нейтраль", запис)
                    continue
                t = self.комплекс["вершини"][номер][вісь]
                self.assertEqual(вершина["стан"] == "визначено", у_області(запис["область"], t),
                                 (ребро, номер))
                перевірено += 1
        ЛІЧБА["вершини_ребер"] = перевірено

    def test_ребра_кінців_V(self):
        """За V=0/10 і C>0 образу немає; прямий метод відмовляє по всій довжині ребра."""
        проби = 0
        for ребро, запис in zip(self.комплекс["ребра"], self.вихід["ребра"]):
            if запис["клас"] != "кінець V":
                continue
            self.assertEqual(запис["область"], [])
            низ, верх = (МОДУЛЬ.ЗШИВАННЯ.число(x) for x in ребро["інтервал"])
            for t in ([низ + (верх - низ) * t for t in ЧАСТКИ] if math.isfinite(верх)
                      else [низ + d for d in (0, 1, 10, 100)]):
                H, V, C = точка(ребро["вісь"], ребро["фіксовані"], t)
                if C > 0:
                    with self.assertRaises((AssertionError, ValueError)):
                        self.бібліотека.notation.munsell_colour_to_xyY(
                            f"{МОДУЛЬ.ОСНОВА.позначення(H, 5, C).split()[0]} {V:g}/{C:.12g}")
                    проби += 1
        ЛІЧБА["кінці_V"] = проби


if __name__ == "__main__":
    результат = unittest.main(exit=False, verbosity=1).result
    print(json.dumps(ЛІЧБА, ensure_ascii=False))
    sys.exit(not результат.wasSuccessful())
