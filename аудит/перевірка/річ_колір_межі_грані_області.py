"""Звіряє клітинки областей граней прямим методом і з областями всіх їхніх ребер.

Власна перевірка виконавця, не незалежне приймання сімей.
Запуск із кореня: python аудит/перевірка/річ_колір_межі_грані_області.py
"""
import importlib.util
import json
import math
from pathlib import Path
import random
import sys
import tempfile
import unittest
from unittest.mock import patch
import warnings


КОРІНЬ = Path(__file__).resolve().parents[2]
ШЛЯХ = КОРІНЬ / "джерела/лабораторія/колір_сім_ї_грані_області.py"
СПЕЦИФІКАЦІЯ = importlib.util.spec_from_file_location("грані_області", ШЛЯХ)
МОДУЛЬ = importlib.util.module_from_spec(СПЕЦИФІКАЦІЯ)
СПЕЦИФІКАЦІЯ.loader.exec_module(МОДУЛЬ)
ОСНОВА, РЕБРА, ТОН, ЗШИВАННЯ = МОДУЛЬ.ОСНОВА, МОДУЛЬ.РЕБРА, МОДУЛЬ.ТОН, МОДУЛЬ.ЗШИВАННЯ
ЧАСТКИ = [i / 40 for i in range(41)]
ЛІЧБА = {}


def прямо(перетворити, H, V, C):
    """Відповідь попередніх методів: (визначено, причина відмови)."""
    if not РЕБРА.СКІНЧЕННІ.визначено_V(V):
        return False, "дані"
    try:
        перетворити(H, V, C)
    except (AssertionError, ValueError) as помилка:
        return False, "XYZ" if "Непридатний XYZ" in str(помилка) else "дані"
    return True, None


def число(x):
    """Читає «+inf» збереженого виходу."""
    return math.inf if x == "+inf" else x


def у_частині(частина, x):
    """Належність координати частині [від, до] із замкненістю кінців."""
    від, до, зв, зд, _ = частина
    від, до = число(від), число(до)
    return від < x < до or (x == від and зв) or (x == до and зд)


def стан(грань, точка):
    """Стан клітинки, що містить точку H/V/C, або None поза гранню."""
    осі = ["HVC".index(x) for x in грань["осі"]]
    рядки = [i for i, ч in enumerate(грань["частини"][0]) if у_частині(ч, точка[осі[0]])]
    стовпці = [j for j, ч in enumerate(грань["частини"][1]) if у_частині(ч, точка[осі[1]])]
    if len(рядки) != 1 or len(стовпці) != 1:
        return None
    return грань["стани"][рядки[0]][стовпці[0]]


def у_області(область, t):
    """Читає збережене об'єднання інтервалів із замкненістю кінців."""
    for x in область:
        if (x["від"] < t < x["до"] or (t == x["від"] and x["замкнено"][0])
                or (t == x["до"] and x["замкнено"][1])):
            return True
    return False


class ПеревіркаГраней(unittest.TestCase):
    """Відтворення, покриття, клітинки проти прямого методу, узгодження з ребрами."""

    @classmethod
    def setUpClass(клас):
        """Читає збережений вихід, межі, зшивання, ребра та прямий метод."""
        warnings.filterwarnings("ignore")
        клас.вихід = json.loads(МОДУЛЬ.ВИХІД.read_text(encoding="utf-8"))
        клас.межі = json.loads(ОСНОВА.ВХІД.read_text(encoding="utf-8"))["межі"]
        клас.комплекс = json.loads(РЕБРА.ВХІД.read_text(encoding="utf-8"))
        клас.ребра = json.loads(РЕБРА.ВИХІД.read_text(encoding="utf-8"))["ребра"]
        клас.тону = {x["ребро"]: x for x in json.loads(ТОН.ВИХІД.read_text(encoding="utf-8"))["ребра"]}
        клас.бібліотека = ОСНОВА.залежності()
        клас.перетворити = staticmethod(ОСНОВА.зробити_перетворення(клас.бібліотека))

    def test_відтворення_та_підміна(self):
        """Повторне породження побайтове; підміна ребер тону — відмова до породження граней."""
        текст = МОДУЛЬ.серіалізувати(МОДУЛЬ.породити())
        self.assertEqual(текст.encode(), МОДУЛЬ.ВИХІД.read_bytes())
        with tempfile.TemporaryDirectory() as тека:
            підміна = Path(тека) / "тону.json"
            підміна.write_text(ТОН.ВИХІД.read_text(encoding="utf-8").replace(
                '"V": 1.5', '"V": 1.25', 1), encoding="utf-8")
            with patch.object(ТОН, "ВИХІД", підміна), self.assertRaises(ValueError):
                МОДУЛЬ.породити()

    def test_покриття(self):
        """Усі 234 грані; частини кожної осі суміжні й покривають інтервал грані без перекриття."""
        self.assertEqual([x["грань"] for x in self.вихід["грані"]], list(range(len(self.межі))))
        for грань, межа in zip(self.вихід["грані"], self.межі):
            if грань.get("нейтраль"):
                self.assertEqual([межа["вісь"], межа["координата"]], ["C", 0.0])
                continue
            self.assertEqual(len(грань["стани"]), len(грань["частини"][0]))
            for назва, вісь, інтервал in zip(грань["осі"], грань["частини"], межа["інтервали"]):
                низ, верх = (ЗШИВАННЯ.число(x) for x in інтервал)
                # C=0 — нейтраль окремим методом: частина хроми від неї відкрита.
                self.assertEqual((вісь[0][0], вісь[0][2]), (низ, not (назва == "C" and низ == 0)))
                self.assertEqual(число(вісь[-1][1]), верх)
                for a, b in zip(вісь, вісь[1:]):
                    self.assertTrue(a[1] == b[0] and a[3] != b[2]
                                    or math.nextafter(a[1], math.inf) == b[0] and a[3] and b[2])
            for рядок in грань["стани"]:
                self.assertEqual(len(рядок), len(грань["частини"][1]))
        ЛІЧБА["граней"] = len(self.вихід["грані"])

    def test_клітинки_прямим_методом(self):
        """Центр і дві випадкові точки кожної клітинки, кути — у 3 000 випадкових клітинках."""
        генератор, лічба = random.Random(13), {}
        клітинки = [(г, i, j) for г in self.вихід["грані"] if not г.get("нейтраль")
                    for i in range(len(г["частини"][0])) for j in range(len(г["частини"][1]))]
        кути = set(генератор.sample(range(len(клітинки)), 3000))
        for номер, (грань, i, j) in enumerate(клітинки):
            частини = [грань["частини"][0][i], грань["частини"][1][j]]
            значення = []
            for від, до, зв, зд, _ in частини:
                від, до = число(від), min(число(до), число(від) + 1000)
                варіанти = [(від + до) / 2] + [генератор.uniform(від, до) for _ in range(2)]
                if номер in кути:
                    варіанти += [x for x, з in ((від, зв), (до, зд)) if з]
                значення.append(варіанти)
            очікуване = грань["стани"][i][j]
            for k, a in enumerate(значення[0]):
                for b in (значення[1] if k == 0 or номер in кути else значення[1][k:k + 1]):
                    точка = [0.0] * 3
                    точка["HVC".index(грань["фіксована"][0])] = грань["фіксована"][1]
                    точка["HVC".index(грань["осі"][0])] = a
                    точка["HVC".index(грань["осі"][1])] = b
                    if not у_частині(частини[0], a) or not у_частині(частини[1], b):
                        continue
                    визначено, причина = прямо(self.перетворити, *точка)
                    ключ = очікуване + ("+" if визначено else причина)
                    лічба[ключ] = лічба.get(ключ, 0) + 1
                    if очікуване == "+":
                        self.assertTrue(визначено, (грань["грань"], точка))
                    elif очікуване == "-":
                        self.assertEqual(причина, "дані", (грань["грань"], точка))
                    elif очікуване == "z":
                        self.assertEqual(причина, "XYZ", (грань["грань"], точка))
        ЛІЧБА["клітинки"] = лічба

    def test_узгодження_з_ребрами(self):
        """Кожне ребро кожної грані: стан клітинки вздовж ребра збігається з областю ребра."""
        перевірено, пропущено = 0, 0
        for номер, ребро in enumerate(self.комплекс["ребра"]):
            запис = self.тону.get(номер) or self.ребра[номер]
            if запис["клас"] in ("нейтральна точка", "нейтральний відрізок"):
                continue
            вісь = "HVC".index(ребро["вісь"])
            низ, верх = (ЗШИВАННЯ.число(x) for x in ребро["інтервал"])
            верх_проб = min(верх, низ + 1000)
            точки = {низ + (верх_проб - низ) * t for t in ЧАСТКИ}
            for x in запис.get("область", []):
                for кінець in (x["від"], x["до"]):
                    точки |= {кінець, math.nextafter(кінець, math.inf), math.nextafter(кінець, -math.inf)}
            for посилання in ребро["грані"]:
                грань = self.вихід["грані"][ЗШИВАННЯ.розпакувати(посилання)[0]]
                if грань.get("нейтраль"):
                    continue
                for t in sorted(x for x in точки if низ <= x <= верх_проб and not (вісь == 2 and x == 0)):
                    точка = list(ребро["фіксовані"])
                    точка.insert(вісь, t)
                    стан_клітинки = стан(грань, точка)
                    # H=1 і H=101 ототожнено зшиванням.
                    if стан_клітинки is None and точка[0] in (1.0, 101.0):
                        стан_клітинки = стан(грань, [102.0 - точка[0], *точка[1:]])
                    self.assertIsNotNone(стан_клітинки, (номер, грань["грань"], точка))
                    if стан_клітинки == "x":
                        пропущено += 1
                        continue
                    self.assertEqual(стан_клітинки == "+", у_області(запис["область"], t),
                                     (номер, грань["грань"], точка, стан_клітинки))
                    перевірено += 1
        ЛІЧБА["узгодження"] = {"перевірено": перевірено, "у_клітинках_x": пропущено}


if __name__ == "__main__":
    результат = unittest.main(exit=False, verbosity=1).result
    print(json.dumps(ЛІЧБА, ensure_ascii=False))
    sys.exit(not результат.wasSuccessful())
