"""Відтворює мірило на заданому дереві та зберігає завершені журнали."""
import json
import os
from pathlib import Path
import subprocess
import sys
import time


def main():
    """Послідовно запускає мірило, а для ПІСЛЯ — батарею та проби типу."""
    дерево = Path(sys.argv[1]).resolve()
    етап = sys.argv[2]
    вихід = Path(__file__).resolve().parent
    команди = [
        ("поверхня", ["джерела/проби/поверхня_212.py"], дерево),
        ("каталог", ["аудит/перевірка/2075/власні_проби.py", str(дерево)], дерево),
        ("фото", ["аудит/перевірка/2075/мірило_каталогу.py"], дерево),
    ]
    if етап.startswith("ПІСЛЯ"):
        джерела = дерево / "джерела"
        команди += [(ім, [шлях], джерела) for ім, шлях in [
            ("дим", "стенд_знімок.py"), ("живий-шлях", "тест_живого_шляху.py"),
            ("протокол", "тест_протоколу.py"), ("розділи", "прилади/розділи_гейтів.py"),
            ("контракти", "audit_contracts.py"),
        ]]
        команди[3][1].append("--дим")
        команди += [(п.stem, [str(п)], джерела)
                    for п in sorted((джерела / "проби").glob("колір_тип_213*.py"))]
        команди += [(ім, ["проби/" + ім + ".py"], джерела) for ім in
                    ("колір_сегменти_213", "поверхня_1993_невизначеність",
                     "поверхня_1993_тотожність", "поверхня_212_тип")]
        команди += [(ім, ["проби/" + ім + ".py"], джерела) for ім in
                    ("шлях_речі_вимір_проти_слова", "foto_rechi_152",
                     "пул_порядок_500_2030", "колір_центр_вікна_хрома", "поділ_жнива_офлайн")]
        команди.append(("дошка", ["джерела/прилади/згорнути_дошку.py", "--лише-перевірити"], дерево))
        команди.append(("показ", ["node", "тест_показу.js"], джерела))
    результати = []
    for ім, аргументи, тека in команди:
        команда = аргументи if аргументи[0] == "node" else [sys.executable, "-X", "utf8", *аргументи]
        початок = time.monotonic()
        оточення = dict(os.environ, PYTHONUTF8="1", PYTHONIOENCODING="utf-8",
                        NODE_PATH=str(дерево / "джерела/node_modules"))
        with (вихід / (етап + "-" + ім + ".txt")).open("w", encoding="utf-8") as журнал:
            процес = subprocess.run(команда, cwd=тека, env=оточення, stdout=журнал, stderr=subprocess.STDOUT)
        факт = dict(назва=ім, команда=команда, тека=str(тека), код=процес.returncode,
                    секунд=round(time.monotonic() - початок, 1))
        результати.append(факт)
        (вихід / (етап + "-команди.json")).write_text(
            json.dumps(результати, ensure_ascii=False, indent=2), encoding="utf-8")
        print(json.dumps(факт, ensure_ascii=False), flush=True)


if __name__ == "__main__":
    main()
