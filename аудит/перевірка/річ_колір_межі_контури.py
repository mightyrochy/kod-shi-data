def звірити_покриття(перевірка, межі, ділянки):
    """Звіряє кожну відкриту смугу прямокутника без сітки генератора."""
    (H0, H1), (V0, V1) = межі
    краї = sorted({x for ділянка in ділянки for x in ділянка["HV"][0]})
    перевірка.assertEqual((краї[0], краї[-1]), (H0, H1))
    for низ, верх in zip(краї, краї[1:]):
        H = (низ + верх) / 2
        інтервали = sorted(ділянка["HV"][1] for ділянка in ділянки
                           if ділянка["HV"][0][0] < H < ділянка["HV"][0][1])
        перевірка.assertTrue(інтервали)
        край = V0
        for a, b in інтервали:
            перевірка.assertEqual(a, край, "Прогалина або перекриття")
            перевірка.assertGreater(b, a)
            край = b
        перевірка.assertEqual(край, V1)


class ПеревіркаКонтурів(unittest.TestCase):
    """Звіряє область, координати, контроль похибки й відмови методу."""

    @classmethod
    def setUpClass(клас):
        """Читає зафіксовані вхід і вихід, завантажує точну версію бібліотеки."""
        клас.бібліотека = МОДУЛЬ.залежності()
        клас.вхід = json.loads(МОДУЛЬ.ВХІД.read_text(encoding="utf-8"))
        клас.вихід = json.loads(МОДУЛЬ.ВИХІД.read_text(encoding="utf-8"))

    def test_облік_усіх_граней(self):
        """Обрано весь клас, а кожна інша грань має причину відкладення."""
        очікувані = {i for i, грань in enumerate(self.вхід["межі"])
                     if грань["вісь"] == "C" and грань["координата"] > 0
                     and грань["інтервали"][1][0] > 0 and грань["інтервали"][1][1] < 10}
        готові = [грань["грань"] for грань in self.вихід["грані"]]
        відкладені = [грань["грань"] for грань in self.вихід["відкладені"]]
        self.assertEqual(set(готові), очікувані)
        self.assertEqual(len(готові), len(очікувані))
        self.assertFalse(set(готові) & set(відкладені))
        self.assertEqual(sorted(готові + відкладені), list(range(len(self.вхід["межі"]))))
        self.assertTrue(all(грань["причина"] for грань in self.вихід["відкладені"]))

    def test_повне_покриття(self):
        """Кожен повний прямокутник джерела покрито рівно один раз."""
        for грань in self.вихід["грані"]:
            джерело = self.вхід["межі"][грань["грань"]]
            self.assertEqual(грань["джерело"], джерело)
            звірити_покриття(self, джерело["інтервали"], грань["ділянки"])

    def test_походження(self):
        """Звіряє хеші джерел, алгоритму й використаних модулів перетворення."""
        for запис in self.вихід["походження"]:
            назва = запис["файл"]
            if назва.startswith("colour/"):
                шлях = Path(self.бібліотека.__file__).parent / назва.removeprefix("colour/")
            elif (МОДУЛЬ.ВХІД.parent / назва).is_file():
                шлях = МОДУЛЬ.ВХІД.parent / назва
            else:
                шлях = МОДУЛЬ.ДЖЕРЕЛА / назва
            хеш = hashlib.sha256(шлях.read_text(encoding="utf-8").encode("utf-8")).hexdigest()
            self.assertEqual(хеш, запис["sha256_lf"], назва)

    def test_область_renotation(self):
        """Звіряє стелю C на кожному інтерполяційному прямокутнику H/V."""
        from colour.notation.munsell import (maximum_chroma_from_renotation,
                                            munsell_colour_to_munsell_specification)
        прямокутників = 0
        запас = math.inf
        for грань in self.вихід["грані"]:
            H, V = грань["джерело"]["інтервали"]
            C = грань["джерело"]["координата"]
            # До V=9 стеля — мінімум чотирьох вузлів і стала всередині
            # кожної смуги 2.5H × 1V. Вище 9 вона монотонно падає:
            # у такій смузі беремо верхній V, а не лише її середину.
            for (H0, H1), (V0, V1) in itertools.product(
                    МОДУЛЬ.поділити(H, [2.5 * i for i in range(41)]),
                    МОДУЛЬ.поділити(V, range(11))):
                світлота = V1 if V1 > 9 else (V0 + V1) / 2
                специфікація = munsell_colour_to_munsell_specification(
                    МОДУЛЬ.позначення((H0 + H1) / 2, світлота, C))
                h, світлота, _, код = специфікація
                стеля = maximum_chroma_from_renotation([h, світлота, код])
                self.assertLessEqual(C, стеля, грань["грань"])
                запас = min(запас, стеля - C)
                прямокутників += 1
        print(f"Область renotation: {прямокутників} прямокутників; мінімальний запас C {запас}")

    def test_позначення_без_зсуву(self):
        """Перевіряє початок, кінці сімей і циклічний шов ASTM."""
        for H, назва in ((1, "1R"), (10, "10R"), (20, "10YR"),
                         (60, "10BG"), (100, "10RP"), (101, "1R")):
            self.assertEqual(МОДУЛЬ.позначення(H, 5, 2), f"{назва} 5/2")

    def test_непридатні_координати(self):
        """Необмежене, нейтраль і кінці V не отримують вигаданого тону."""
        for точка in ((1, 0, 2), (1, 10, 2), (1, 5, 0), (1, 5, math.inf),
                      (math.nan, 5, 2), (0, 5, 2)):
            with self.assertRaises(ValueError):
                МОДУЛЬ.позначення(*точка)

    def test_незалежне_перетворення_освітлювача(self):
        """Зіставляє Bradford/Lab репозиторію з реалізацією Colour."""
        colour = self.бібліотека
        перетворити = МОДУЛЬ.зробити_перетворення(colour)
        for H, V, C in ((1, 5, 2), (14.2, 8.1, 5.3), (42, 3, 1.5),
                        (67, 6, 7), (99, 5, 6), (101, 5, 2)):
            xyz = colour.xyY_to_XYZ(colour.notation.munsell_colour_to_xyY(
                МОДУЛЬ.позначення(H, V, C)))
            xyz = colour.adaptation.chromatic_adaptation_VonKries(
                xyz, МОДУЛЬ.БІЛІ["C"], МОДУЛЬ.БІЛІ["D65"], transform="Bradford")
            lab = colour.XYZ_to_Lab(xyz, illuminant=colour.XYZ_to_xy(МОДУЛЬ.БІЛІ["D65"]))
            self.assertLess(math.dist(lab, перетворити(H, V, C)[0]), 1e-10)
        self.assertEqual(перетворити(1, 5, 2), перетворити(101, 5, 2))
        # Відомий приклад документації Colour; ASTM уже містить поправку MgO.
        xyY = colour.notation.munsell_colour_to_xyY("4.2YR 8.1/5.3")
        self.assertLess(math.dist(xyY, (0.3873694, 0.3575165, 0.59362)), 1e-7)

    def test_записані_похибки(self):
        """Усі записані проби відповідають цілям, усі координати скінченні."""
        for грань in self.вихід["грані"]:
            for ділянка in грань["ділянки"]:
                for вид in ("контроль", "перевірка"):
                    for похибка, ціль in zip(ділянка[вид], self.вихід["цілі_похибки"]):
                        self.assertTrue(0 <= похибка <= ціль)
                self.assertTrue(all(math.isfinite(x) for вузол in ділянка["вузли"]
                                    for простір in вузол for x in простір))

    def test_стикування_ділянок(self):
        """Міряє розходження інтерполянтів на всіх внутрішніх стиках ділянок."""
        максимуми = [0.0] * 4
        проб = 0
        for грань in self.вихід["грані"]:
            ребра = collections.defaultdict(lambda: ([], []))
            for ділянка in грань["ділянки"]:
                for вісь in (0, 1):
                    for бік, координата in enumerate(ділянка["HV"][вісь]):
                        ребра[вісь, координата][бік].append(ділянка)
            for (вісь, координата), (плюс, мінус) in ребра.items():
                for a, b in itertools.product(плюс, мінус):
                    низ = max(a["HV"][1 - вісь][0], b["HV"][1 - вісь][0])
                    верх = min(a["HV"][1 - вісь][1], b["HV"][1 - вісь][1])
                    if низ >= верх:
                        continue
                    for інша in (низ, (низ + верх) / 2, верх):
                        точка = (координата, інша) if вісь == 0 else (інша, координата)
                        значення = []
                        for ділянка in (a, b):
                            u, v = ((x - lo) / (hi - lo) for x, (lo, hi) in zip(точка, ділянка["HV"]))
                            lab = МОДУЛЬ.наблизити([вузол[0] for вузол in ділянка["вузли"]], u, v)
                            значення.append((lab, МОДУЛЬ.координати_з_lab(lab)))
                        максимуми = list(map(max, максимуми, МОДУЛЬ.похибки(*значення)))
                        проб += 1
        self.assertTrue(all(x <= 2 * ціль for x, ціль in zip(максимуми, self.вихід["цілі_похибки"])))
        print(f"Стики: {проб} проб; максимальні розходження ΔLab76/θ/L*/C*: {максимуми}")

    def test_додаткові_точки_кожної_грані(self):
        """Міряє інші точки з округленого файла, поза пробами генератора."""
        перетворити = МОДУЛЬ.зробити_перетворення(self.бібліотека)
        максимуми = [0.0] * 4
        проб = 0
        for грань in self.вихід["грані"]:
            ділянки = грань["ділянки"]
            for i in sorted({0, len(ділянки) // 2, len(ділянки) - 1}):
                ділянка = ділянки[i]
                похибки = МОДУЛЬ.перевірити_ділянку(
                    перетворити, грань["джерело"]["координата"], ділянка["HV"], ділянка["вузли"],
                    [(0.137, 0.619), (0.863, 0.381)])
                максимуми = list(map(max, максимуми, похибки))
                проб += 2
        self.assertTrue(all(x <= ціль for x, ціль in zip(максимуми, self.вихід["цілі_похибки"])))
        print(f"Додаткових проб: {проб}; максимуми ΔLab76/θ/L*/C*: {максимуми}")

    def test_кривизна_й_шов(self):
        """Внутрішній вигин ділиться навіть при точних кутах; шов не розривається."""
        def вигин(H, V, C):
            """Дає поверхню з нульовою висотою на всіх чотирьох краях."""
            lab = (50 + H, C + V, 10 + 4 * H * (1 - H) * V * (1 - V))
            return lab, МОДУЛЬ.координати_з_lab(lab)
        ділянки = list(МОДУЛЬ.породити_ділянки(вигин, 2, ((0, 1), (0, 1))))
        self.assertGreater(len(ділянки), 1)
        звірити_покриття(self, ((0, 1), (0, 1)), ділянки)
        self.assertEqual(МОДУЛЬ.розгорнути(1, 359), 361)
        self.assertEqual(МОДУЛЬ.розгорнути(359, 1), -1)

    def test_відмова_замість_неперевіреного(self):
        """Недостатня дозволена глибина завершується явною відмовою."""
        def вигин(H, V, C):
            """Дає завелику похибку лінійного наближення."""
            lab = (50 + H, C + V, 10 + H * H * 100)
            return lab, МОДУЛЬ.координати_з_lab(lab)
        with self.assertRaises(ValueError):
            list(МОДУЛЬ.породити_ділянки(вигин, 2, ((0, 1), (0, 1)),
                                      МОДУЛЬ.РЕЄСТР["глибина"]["val"]))


