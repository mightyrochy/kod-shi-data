"""Крок 24а (б): порівняння знімків `знімок.py` до і після переходу воріт певності тону, підтону й темного бурого
на сім'ї `колір_тон` — з причиною кожного переходу.

    python3 -W ignore аудит/перевірка/річ_колір_межі_крок24а/порівняти_б.py <до.json.gz> <після.json.gz>

Геометрія відношень після (а) тотожна (знімок (а) = знімок кроку 23 побайтово), тож вердикт класу тону пари
змінюється лише через певність тону τ її записів (`сила` множить вікно на τa·τb; `achromatic` — 1 − τa·τb;
`tonal`, `echo` — через `same_hue`), `warm_cool` — через певність підтону, акцент — через τ² і темне буре. Скрипт
перевіряє це для кожної зміненої пари (пар без зміненого τ чи підтону має бути 0) і розкладає зміни τ точок
каталогу за сім'єю (`колір_тон.сім_я_кольору`), смугою C* і L*."""
import collections, gzip, json, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "джерела"))
import колір_тон as Т, колір_річ as КР, verify as V  # noqa: E402
from colorspace import lch  # noqa: E402

до, після = (json.load(gzip.open(ф, "rt")) for ф in sys.argv[1:3])
в = lambda с: "так" if с[0] >= 0.5 else "ні" if с[1] < 0.5 else "невідомо"
тч = {"т:%s" % р[0]: [float(x) for x in р[1]] for р in json.load(gzip.open(
    Path(__file__).resolve().parents[1] / "річ_колір_межі_тон_20261105/каталог_точки.json.gz", "rt")) if р[1] is not None}


def смуга(x, межі):
    return next(("<%g" % м for м in межі if x < м), "≥%g" % межі[-1])


# 1. Записи: τ і акцент
τзм = {к for к in до["записи"] if до["записи"][к][1] != після["записи"][к][1]}
кошик = collections.Counter(); при = collections.defaultdict(list)
for к in sorted(τзм):
    if not к.startswith("т:"):
        continue
    lab = тч[к]; L, Cc, h = lch(lab)
    сім = Т.сім_я_кольору(lab)[0]
    τд, τп = до["записи"][к][1][0], після["записи"][к][1][0]
    ключ = (сім, смуга(Cc, (4, 8, 12, 20)), "→".join((в((τд, τд)), в((τп, τп)))))
    кошик[ключ] += 1
    if len(при[ключ]) < 2:
        при[ключ].append("%s Lab(%.0f, %.0f, %.0f) C* %.1f τ %.2f→%.2f" % (к, *lab, Cc, τд, τп))
print("τ точок змінився: %d з %d; вердикт τ (зріз 0.5) за сім'єю, смугою C*:" % (
    sum(к.startswith("т:") for к in τзм), sum(к.startswith("т:") for к in до["записи"])))
for ключ, n in sorted(кошик.items(), key=lambda x: (x[0][2] == "ні→ні" or x[0][2] == "так→так", -x[1])):
    print("   %5d  %-12s C* %-4s τ %s  %s" % (n, *ключ, "; ".join(при[ключ])))
print("вікна слів (τ, акцент ДО → ПІСЛЯ):")
for к in sorted(до["записи"]):
    if к.startswith("с:") and до["записи"][к] != після["записи"][к]:
        (ад, τд), (ап, τп) = до["записи"][к], після["записи"][к]
        print("    %-22s τ %s → %s   акцент %s → %s (%s → %s)" % (к, τд, τп, ад, ап, в(ад), в(ап)))
ак = collections.Counter(); ак_при = collections.defaultdict(list)
for к in до["записи"]:
    (ад, τд), (ап, τп) = до["записи"][к], після["записи"][к]
    if в(ад) != в(ап) and к.startswith("т:"):
        lab = тч[к]; L, Cc, h = lch(lab)
        б_до = 1.0 - ад[0] / τд[0] ** 2 if τд[0] > 0 else None
        б_після = 1.0 - ап[0] / τп[0] ** 2 if τп[0] > 0 else None
        причина = ("темне буре %s→%s" % (None if б_до is None else round(б_до, 1), None if б_після is None else round(б_після, 1))
                   if б_до is None or б_після is None or abs(б_до - б_після) > 0.05 else "τ²")
        ключ = (в(ад) + "→" + в(ап), причина.split(" ")[0] + (" " + причина.split(" ")[1] if причина.startswith("темне") else ""),
                Т.сім_я_кольору(lab)[0], смуга(L, (25, 40)))
        ак[ключ] += 1
        if len(ак_при[ключ]) < 2:
            ак_при[ключ].append("%s Lab(%.0f, %.0f, %.0f) %s" % (к, *lab, причина))
print("акцент точок: вердикт змінився у %d (перехід, причина, сім'я, смуга L*):" % sum(ак.values()))
for ключ, n in ак.most_common():
    print("   %5d  %s  %s" % (n, ключ, "; ".join(ак_при[ключ])))

# 2. Пари
класи = collections.Counter(); без_причини = collections.Counter(); wc = collections.Counter()
for к, (вд, сд, сбд) in до["пари"].items():
    вп, сп, сбп = після["пари"][к]
    а, б = к.split("|")
    рід = а[0] + б[0]
    τ_зм = а in τзм or б in τзм
    for кл in вд:
        if вд[кл] != вп[кл]:
            класи[(рід, кл, вд[кл] + "→" + вп[кл])] += 1
            if not τ_зм and кл != "value_step":
                без_причини[кл] += 1
            if кл == "value_step":
                без_причини[кл] += 1
    if сбд != сбп:
        без_причини["warm_cool без певності"] += 1
    if сд != сп:
        пт = [після["записи"][x] for x in (а, б)]
        wc[(рід, в(сд) + "→" + в(сп))] += 1
print("пар %d; вердикт `колір_річ.відношення` змінився у %d класо-пар:" % (len(до["пари"]), sum(класи.values())))
for (рід, кл, п), n in sorted(класи.items()):
    print("   %6d  %s %-13s %s" % (n, рід, кл, п))
print("змінених класо-пар без зміненого τ запису (і value_step, warm_cool без певності): %s" % (dict(без_причини) or 0))
print("warm_cool з певністю: сила змінилась у %d парах; вердикт (рід, перехід): %s" % (sum(wc.values()), dict(wc)))
жз = [ж for ж in до["жінки"] if до["жінки"][ж] != після["жінки"][ж]]
print("bases.відхил змінився:", sum(до["відхил"][к] != після["відхил"][к] for к in до["відхил"]), "· жінки з різницею:", жз)
