def точні_блоки(Г, кеш, labs):
    """Блок ISCC–NBS і сім'я самої точки кожної речі: обернення решітки + уточнення прямим образом."""
    import numpy as np
    Г._робітник_старт()
    точки, межа = Г.вибірка(кеш)
    вузли = np.array(labs, dtype=float)
    H, V, C = Г.обернути(точки, вузли)
    відхил = np.full(len(labs), math.inf)
    for і in range(len(labs)):
        if np.isfinite(V[і]) and 1 <= V[і] <= 9 and C[і] > 1e-9:
            H[і], V[і], C[і], відхил[і], _ = Г.звірити_вузол((tuple(вузли[і]), float(H[і]), float(V[і]), float(C[і])))
        elif np.isfinite(V[і]):
            відхил[і] = 0.0   # нейтраль, V < 1 чи V > 9: прямого образу Colour нема, лінійно між точками джерела
    сім_ї, клітинки = Г.клітинки_сімей()
    є = np.isfinite(V) & (V >= 0) & (відхил <= Г.РЕЄСТР["межа_звороту"]["val"])
    є &= (V < 1) | (C <= Г.межа_C(np.nan_to_num(H, nan=1.0), np.nan_to_num(V, nan=1.0), межа) + 1e-9)
    блок, сім_я = Г.мітки(np.nan_to_num(H, nan=1.0), np.nan_to_num(V), np.nan_to_num(C), клітинки)
    тон, частка = Г.тон_і_ворота(H, V, C, сім_я, сім_ї, клітинки, КТ.РЕЄСТР["значна_сила"]["val"])
    рівні = Г.РЕЄСТР["рівні_воріт"]["val"]
    вихід = []
    for і in range(len(labs)):
        if not є[і]:
            причина = "поза оболонкою точок renotation" if not np.isfinite(V[і]) else "поза даними renotation"
            вихід.append({"блок": None, "сім_я": None, "причина": причина})
        else:
            вихід.append({"блок": int(блок[і]), "сім_я": сім_ї[int(сім_я[і])] if сім_я[і] < len(сім_ї) else None,
                          "H": round(float(H[і]), 2), "V": round(float(V[і]), 2), "C": round(float(C[і]), 2),
                          "відхил": round(float(відхил[і]), 4), "темна_смуга": bool(V[і] < 1),
                          "тон": сім_ї[int(тон[і])], "частка_тону": round(int(частка[і]) / (рівні - 1), 2),
                          "очікувана": сім_ї[int(тон[і])] if частка[і] * 2 >= рівні - 1 else "achromatic",
                          "світла_смуга": bool(V[і] > 9)})
    return вихід


def причина_невідомо(сили, точне):
    """Чому вердикт — «невідомо»: межа сімей (сили поділено) чи нема даних (вузли без мітки)."""
    без = сили.get(НЕВІДОМО, 0.0)
    сім_ї = [(к, с) for к, с in сили.items() if к != НЕВІДОМО]
    if без >= 0.5:
        return "без даних: " + (точне["причина"] if точне["блок"] is None else "ядро біля краю даних")
    if len(сім_ї) >= 2:
        return f"межа {сім_ї[0][0]}/{сім_ї[1][0]}"
    return "частково без даних"


def медіана(значення):
    return round(statistics.median(значення), 1) if значення else None


def переходи(записи, описи):
    """Матриця ДО → ПІСЛЯ: кожна клітинка з причинами обох боків і медіанами положення."""
    клітинки = collections.defaultdict(list)
    for з in записи:
        клітинки[(з["до"], з["після"])].append(з)
    вихід = []
    for (до, після), р in sorted(клітинки.items(), key=lambda п: -len(п[1])):
        причини_до = collections.Counter(з["причина_до"] for з in р).most_common(3)
        if після == НЕВІДОМО:
            причини_після = collections.Counter(з["причина_після"] for з in р).most_common(4)
        else:
            блоки = collections.Counter(з["точне"]["блок"] for з in р if з["точне"]["блок"]).most_common(4)
            причини_після = [(f"блок {б} ({описи[після.split('+')[0]]['блоки']})", н) for б, н in блоки]
        lch = [КП.lch(з["lab"]) for з in р]
        V = [з["точне"]["V"] for з in р if з["точне"]["блок"]]
        Cм = [з["точне"]["C"] for з in р if з["точне"]["блок"]]
        вихід.append({
            "до": до, "після": після, "речей": len(р),
            "чому_до": [f"{п} ×{н}" for п, н in причини_до],
            "чому_після": [f"{п} ×{н}" for п, н in причини_після],
            "медіана_L*_C*_h": [медіана([x[0] for x in lch]), медіана([x[1] for x in lch]),
                                медіана([x[2] for x in lch])],
            "медіана_Munsell_V_C": [медіана(V), медіана(Cм)],
            "приклади": [з["id"] for з in sorted(р, key=lambda з: з["id"])[:3]],
        })
    return вихід


def сім_ї_вердикту(вердикт):
    """Множина сімей вердикту: «a+b» — обидві, «невідомо» — порожня."""
    return frozenset() if вердикт == НЕВІДОМО else frozenset(вердикт.split("+"))


def пари_слова(записи, ключ):
    """Пари речей з одним словом кольору крамниці: сім'ї перетинаються — так, ні — ні, хоч одна невідома — невідомо."""
    за_словом = collections.defaultdict(list)
    for з in записи:
        if з["слово"]:
            за_словом[з["слово"].strip().lower()].append(сім_ї_вердикту(з[ключ]))
    лічба = collections.Counter()
    for сім_ї in за_словом.values():
        н = collections.Counter(сім_ї)
        відомі = [(м, к) for м, к in н.items() if м]
        невід = н.get(frozenset(), 0)
        усі, всіх_відомих = len(сім_ї), sum(к for _, к in відомі)
        так = sum(к * (к - 1) // 2 for _, к in відомі)
        так += sum(к1 * к2 for і, (м1, к1) in enumerate(відомі) for м2, к2 in відомі[і + 1:] if м1 & м2)
        лічба["так"] += так
        лічба["ні"] += всіх_відомих * (всіх_відомих - 1) // 2 - так
        лічба["невідомо"] += усі * (усі - 1) // 2 - всіх_відомих * (всіх_відомих - 1) // 2
    return dict(лічба)


def слова_вгорі(записи, n=15):
    """Розподіл сімей ДО і ПІСЛЯ для найчастіших слів кольору крамниць."""
    за_словом = collections.defaultdict(list)
    for з in записи:
        if з["слово"]:
            за_словом[з["слово"].strip().lower()].append(з)
    вихід = []
    for слово, р in sorted(за_словом.items(), key=lambda п: -len(п[1]))[:n]:
        вихід.append({"слово": слово, "речей": len(р),
                      "до": dict(collections.Counter(з["до"] for з in р).most_common(4)),
                      "після": dict(collections.Counter(з["після"] for з in р).most_common(5))})
    return вихід


def звірка_граней():
    """Вузли Lab-граней лабораторії (C- і H/V-грані між двома сім'ями): чи ділять їх саме ці дві сім'ї."""
    лічба = collections.Counter()
    розриви = []
    for файл in ("колір_сім_ї_контури.json", "колір_сім_ї_контури_hv.json"):
        дані = json.loads((ДЖЕРЕЛА / "лабораторія" / файл).read_text(encoding="utf-8"))
        for грань in дані["грані"]:
            пара = set(грань["джерело"]["сім_ї"])
            for ділянка in грань["ділянки"]:
                for вузол in ділянка["вузли"][::4]:
                    lab = вузол[0]
                    сили = КТ.сили_сімей(lab)
                    if сили.get(НЕВІДОМО, 0) >= 0.5:
                        лічба["без даних (поза полем sRGB чи V<1)"] += 1
                        continue
                    дві = [к for к, _ in КТ.сім_ї_кольору(lab)]
                    if set(дві) == пара:
                        лічба["вердикт — пара грані"] += 1
                    elif пара & set(дві[:1]):
                        лічба["найсильніша з пари, вердикт без другої чи з іншою"] += 1
                    else:
                        лічба["найсильніша поза парою"] += 1
                        розриви.append({"грань": грань["грань"], "пара": sorted(пара), "lab": lab,
                                        "сили": {к: round(с, 3) for к, с in list(сили.items())[:3]}})
    return dict(лічба), розриви[:10]


