def ворота_блоків(записи):
    """Барвні блоки ISCC–NBS приглушеного (точний блок речі барвний, Munsell C ≤ 4): речей, медіана C* і C Мансела,
    медіана сили ахроматичної в речі (ворота хроми Мансела за тоном і світлотою) і скільки з них — бура сім'я
    приглушеного (`приглушене` генератора: помаранчева, жовта й рожева поза рожевим підтоном, V < 8)."""
    за_блоком = collections.defaultdict(list)
    for з in записи:
        т = з["точне"]
        if т["блок"] and т["сім_я"] not in (None, "achromatic") and т["C"] <= 4.0:
            за_блоком[(т["блок"], т["сім_я"])].append(
                (КП.lch(з["lab"])[1], т["C"], з["сили"].get("achromatic", 0.0), найсильніша(з) == "brown"))
    return [{"блок": б, "сім_я": с, "речей": len(р), "медіана_C*": медіана([x[0] for x in р]),
             "медіана_C_Мансела": медіана([x[1] for x in р]),
             "медіана_сили_ахроматичної": round(statistics.median(x[2] for x in р), 2),
             "найсильніша_бура": sum(x[3] for x in р)}
            for (б, с), р in sorted(за_блоком.items(), key=lambda п: -len(п[1]))]


def hex_з_lab(lab):
    r, g, b = КП.to_rgb(*lab)
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(255 * x))) for x in (r, g, b))


def свотчі(записи, n=40):
    """Граничні речі: на кожну пару сусідніх сімей — одна на самій межі (сили майже порівну: проба хибної
    відмови) і одна з іншого боку з вердиктом сили 0.55–0.85 (проба хибного прийняття біля межі)."""
    за_парою = collections.defaultdict(list)
    for з in записи:
        сили = [(к, с) for к, с in з["сили"].items() if к != НЕВІДОМО]
        if len(сили) < 2 or з["сили"].get(НЕВІДОМО, 0) >= 0.2:
            continue
        (к1, с1), (к2, с2) = сили[:2]
        if с2 < 0.1:
            continue
        за_парою[tuple(sorted((к1, к2)))].append((к1, с1, с2, з))
    вибрані = []
    for пара, р in sorted(за_парою.items(), key=lambda п: (-len(п[1]), п[0])):
        межа = min(р, key=lambda x: (x[1] - x[2], x[3]["id"]))
        інший = [x for x in р if x[0] != межа[0] and 0.55 <= x[1] <= 0.85]
        if not інший:
            continue
        біля = min(інший, key=lambda x: (abs(x[1] - 0.7), x[3]["id"]))
        вибрані += [(пара, межа[3]), (пара, біля[3])]
        if len(вибрані) >= n:
            break
    return [{"пара": list(пара), "id": з["id"], "слово": з["слово"], "назва": з["назва"], "lab": з["lab"],
             "hex": hex_з_lab(з["lab"]), "до": з["до"], "після": з["після"],
             "сили": {к: round(с, 3) for к, с in list(з["сили"].items())[:3]},
             "температура": None if з["температура"] is None else round(з["температура"], 2)}
            for пара, з in вибрані[:n]]


