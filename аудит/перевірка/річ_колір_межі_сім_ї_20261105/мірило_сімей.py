def причина_до(lab):
    """Чому чинна `колір_річ.сім_я` дала свою відповідь: гілка K-COL-06 чи дуга кута."""
    L, Cc, h = КП.lch(lab)
    if Cc < ПРАВИЛА["neutral_C"]:
        return f"C*<{ПРАВИЛА['neutral_C']} і b* за порогами"
    if КР._темне_буре(L, Cc, h):
        return "вікно темного бурого"
    lo, hi, cmax = ПРАВИЛА["warm_neutral"]
    if lo - 1e-9 <= h <= hi + 1e-9 and Cc <= cmax + 1e-9:
        return f"коридор теплої нейтралі h {lo}–{hi}, C*≤{cmax}"
    lo, hi, _ = ПРАВИЛА["cool_neutral"]
    if lo - 1e-9 <= h <= hi + 1e-9 and КР.нейтраль(lab) == "холодна":
        return f"коридор холодної нейтралі h {lo}–{hi}"
    for lo, hi, назва in КР.FAMILIES:
        if (lo <= h < hi) if lo < hi else (h >= lo or h < hi):
            return f"дуга h {lo}–{hi}"
    return "поза дугами"


