"""Порівняння двох знімків `мірило_ч8.py` (ДО — база, ПІСЛЯ — голова): тотожне — побайтово; перетин — переходи речей.

    python3 аудит/перевірка/річ_колір_межі_ч8/порівняти_ч8.py <до.json.gz> <після.json.gz> <звіт.json>

Перехід речі — її тон увійшов у спільну дугу двох рис (перегук `resonance` → рядок фіду `h_from`/`h_to`) чи вийшов
з неї; належність — `колір_тон.in_arc` на кінцях дуг, однаковим суддею для ДО і ПІСЛЯ. Причина кожної зміненої дуги:
«сітка» — ті самі шматки, кінці ДО зсунуті всередину сіткою 2°; «вужче за крок» — перетин ДО загублений; «два шматки» —
ДО один шматок через проміжок між двома."""
import collections, gzip, hashlib, json, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "джерела"))
from колір_тон import in_arc, ширина_дуги, дуга_в_дузі
import colorspace as КП

до, після = (json.load(gzip.open(ф, "rt", encoding="utf-8")) for ф in sys.argv[1:3])
f = lambda x: float(x)
ключі = sorted(set(до["тотожне"]) | set(після["тотожне"]))
різні = [к for к in ключі if до["тотожне"].get(к) != після["тотожне"].get(к)]
хеш = lambda x: hashlib.sha256(json.dumps(x, ensure_ascii=False, sort_keys=True).encode()).hexdigest()
точки = [р for р in json.load(gzip.open(Path(__file__).resolve().parents[3] /
                                         "аудит/перевірка/річ_колір_межі_тон_20261105/каталог_точки.json.gz", "rt"))
         if р[1] is not None]
тони = {р[0]: КП.lch(tuple(р[1]))[2] for р in точки}


def дуги(x):
    """Список дуг (кортежів чисел) з ДО (дуга чи None) або ПІСЛЯ (список дуг)."""
    if x is None:
        return []
    if x and not isinstance(x[0], list):
        return [(f(x[0]), f(x[1]))]
    return [(f(a), f(b)) for a, b in x]


def причина(д0, д1):
    """Чому дуги ДО і ПІСЛЯ різні (див. шапку)."""
    if not д0:
        return "вужче за крок"
    if len(д1) > len(д0):
        return "два шматки"
    if len(д0) == len(д1) and all(дуга_в_дузі(a, b) and ширина_дуги(b) - ширина_дуги(a) <= 4.0 + 1e-9
                                  for a, b in zip(д0, д1)):
        return "сітка"
    return "інше"


пари = collections.Counter()
for к, x in до["перетин"].items():
    if к == "риси":
        continue
    д0, д1 = дуги(x), дуги(після["перетин"][к])
    if д0 != д1:
        пари[причина(д0, д1)] += 1
речі = dict(тони)
перегуки, переходи, причини = 0, collections.Counter(), collections.Counter()
приклади = []
for к, р0 in до["перетин"]["риси"].items():
    р1 = після["перетин"]["риси"][к]
    м0 = {tuple(п["риси"]): дуги(п["спільні_дуги"]) for п in р0["resonance"]["перегуки"]}
    м1 = {tuple(п["риси"]): дуги(п["спільні_дуги"]) for п in р1["resonance"]["перегуки"]}
    for пара in sorted(set(м0) | set(м1)):
        д0, д1 = м0.get(пара, []), м1.get(пара, [])
        перегуки += 1
        if д0 == д1:
            continue
        пр = причина(д0, д1)
        причини[пр] += 1
        у0 = {і for і, h in речі.items() if any(in_arc(h, д) for д in д0)}
        у1 = {і for і, h in речі.items() if any(in_arc(h, д) for д in д1)}
        переходи["увійшли"] += len(у1 - у0)
        переходи["вийшли"] += len(у0 - у1)
        if len(приклади) < 12 or пр != "сітка":
            приклади.append(dict(випадок=к, риси=пара, до=д0, після=д1, причина=пр, увійшли=len(у1 - у0),
                                 вийшли=len(у0 - у1)))
    for частина in ("brief",):
        if р0[частина] != р1[частина]:
            причини["brief змінено"] += 1
    if [п["риси"] for п in р0["resonance"]["перегуки"]] != [п["риси"] for п in р1["resonance"]["перегуки"]]:
        причини["набір пар перегуків змінено"] += 1
    for поле in ("напруги", "без_температури", "зони_збігу"):
        if р0["resonance"][поле] != р1["resonance"][поле]:
            причини["змінено " + поле] += 1
звіт = dict(точок=до["точок"], ключів_тотожного=len(ключі), різних=len(різні), різні_ключі=різні[:20],
            sha_тотожного_до=хеш(до["тотожне"]), sha_тотожного_після=хеш(після["тотожне"]),
            пар_каталогу_змінено=dict(пари), пар_каталогу=len(до["перетин"]) - 1,
            перегуків_рис=перегуки, змінених_перегуків=dict(причини), переходи_речей=dict(переходи), приклади=приклади)
Path(sys.argv[3]).write_text(json.dumps(звіт, ensure_ascii=False, indent=1), encoding="utf-8")
print(json.dumps({к: в for к, в in звіт.items() if к != "приклади"}, ensure_ascii=False))
