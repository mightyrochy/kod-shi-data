"""Мірило ч8 кореня Річ-колір-межі: повтор записаних точок каталогу через змінені функції п'яти файлів частини.

Запуск з кореня репозиторію (дерево — корінь репозиторію бази чи голови):

    python3 аудит/перевірка/річ_колір_межі_ч8/мірило_ч8.py <дерево> <вихід.json.gz>

Точки — `аудит/перевірка/річ_колір_межі_тон_20261105/каталог_точки.json.gz` (27 200 речей, 9 535 з Lab) цього
репозиторію; вікна слів — `verify.ЛЕКСИКОН` дерева; риси — `аудит/проби/жінки/ж1–ж9.json` через `міст_вхід.features`.
Для точки i пара — точка i+1, очі — точка i+7, слово — i-те по колу словника. Ключ «тотожне» — функції, чия поведінка
не мала змінитися; «перетин» — `arc_overlap` (перехід на `колір_тон.перетин_дуг`) і все, що з нього йде (`resonance`,
`brief`)."""
import gzip, json, sys
from pathlib import Path

КОРІНЬ = Path(__file__).resolve().parents[3]
ДЕРЕВО = Path(sys.argv[1]).resolve()
sys.path.insert(0, str(ДЕРЕВО / "джерела"))
import colorspace as КП, колір_відношення as ВІД, колір_річ as КР, колір_простір_стеля as СТ
import колір_простір_індукція as ІНД, колір_простір_риси as РИС, колір_хрома as ХР, verify, міст_вхід as МВ


def ч(x):
    """JSON-сумісне значення з повним repr чисел (побайтове порівняння)."""
    if isinstance(x, float):
        return repr(x)
    if isinstance(x, (list, tuple)):
        return [ч(y) for y in x]
    if isinstance(x, dict):
        return {str(k): ч(v) for k, v in x.items()}
    return x if x is None or isinstance(x, (str, int, bool)) else repr(x)


точки = [р for р in json.load(gzip.open(КОРІНЬ / "аудит/перевірка/річ_колір_межі_тон_20261105/каталог_точки.json.gz", "rt"))
         if р[1] is not None]
слова = [(к, в) for к, в in sorted(verify.ЛЕКСИКОН.items())]
n = len(точки)
lch = [КП.lch(tuple(р[1])) for р in точки]
записи = [КР.запис_кольору(dict(lab=list(р[1]))) for р in точки]
записи_слів = [КР.запис_кольору(КР.опора_вікна(L=в[0:2], C=в[2:4], дуга=в[4])) for _, в in слова]
тотожне, перетин = {}, {}
for i, р in enumerate(точки):
    j, k = (i + 1) % n, (i + 7) % n
    L, Cc, h = lch[i]
    Lj, Cj, hj = lch[j]
    ім, в = слова[i % len(слова)]
    дуга_сл = в[4]
    ра, рб, рс, рк = записи[i], записи[j], записи_слів[i % len(слова)], записи[k]
    т = dict(
        кут=ВІД.кут(h, hj), межа=ВІД.межа_за_тоном(h, hj),
        сили=ВІД.сили(ра, рб), сили_слова=ВІД.сили(ра, рс), сили_слова_точки=ВІД.сили(рс, ра),
        в_дузі=ВІД.сила_в_дузі(ра, КП.дуга_кола(hj, 15)), точка_в_дузі=ВІД.сила_точки_в_дузі(Cc, h, КП.дуга_кола(hj, 25)),
        відлуння_очей=ВІД.сила_відлуння_очей(ра, рк),
        c_max=СТ.c_max(L, h), поверхня=СТ.c_max_поверхня(L, h), поверхня_зсув=СТ.c_max_поверхня(L, h - 360.0),
        фантом=СТ.у_фантомній_зоні(L, h), тиск=ІНД.тиск_тону(h, hj, L_речі=L, L_шкіри=Lj),
        огинаюча=ІНД.огинаюча_індукції(h - hj), гучний=ХР._тон_гучного(dict(h=h, C=Cc, хто="річ"))["lab"])
    if дуга_сл is not None:
        т.update(яскравість=ВІД._яскравість(L, Cc, дуга_сл), тепло=ВІД._тепло(дуга_сл),
                 параметри=ВІД._параметри_дуги(дуга_сл), розкид=ВІД.розкид_дуг(дуга_сл, (h, h)),
                 слово_в_дузі=ВІД.сила_в_дузі(ра, дуга_сл))
    тотожне[р[0]] = ч(т)
    перетин[р[0]] = ч(РИС.arc_overlap(КП.дуга_кола(h, 15), КП.дуга_кола(hj, 30)))
тотожне["POINTER_ВУЗЛИ"] = ч(sorted(СТ.POINTER_ВУЗЛИ.items()))
тотожне["ТЕПЛИЙ_ПОЛЮС"] = ч(ВІД.ТЕПЛИЙ_ПОЛЮС)
риси = {}
for н in range(1, 10):
    d = json.load(open(КОРІНЬ / ("аудит/проби/жінки/ж%d.json" % н), encoding="utf-8"))
    F = МВ.features(dict(шкіра=d["skin"], волосся=d["hair"], очі=d["eyes"]))[0]
    тотожне["покриття_ж%d" % н] = ч(ВІД.relation_coverage(F))
    for rel in КП.RELATIONS:
        риси["ж%d/%s" % (н, rel)] = ч(dict(resonance=КП.resonance(F, rel), brief=ВІД.brief(F, rel)))
перетин["риси"] = риси
with gzip.open(sys.argv[2], "wt", encoding="utf-8") as ф:
    json.dump(dict(точок=n, слів=len(слова), тотожне=тотожне, перетин=перетин), ф, ensure_ascii=False, sort_keys=True)
print("точок:", n, "слів:", len(слова))
