"""Крок 22: грані лабораторії (`колір_сім_ї_контури*.json`, таблиця 30.10) проти чинної таблиці сімей: пара грані за
чинною таблицею (клітинки транскрипції по обидва боки грані), і звірка вузлів граней із вердиктом `колір_тон` —
як `мірило_сімей.звірка_граней`, окремо для граней із пару незмінною і зміненою. Запуск із кореня:
python3 -W ignore аудит/перевірка/річ_колір_межі_крок22/грані.py > …/грані.txt"""
import collections, importlib.util, json, sys
from pathlib import Path
sys.path.insert(0, "джерела")
import колір_тон as Т  # noqa: E402
сп = importlib.util.spec_from_file_location("колір_сім_ї_решітка", "джерела/лабораторія/колір_сім_ї_решітка.py")
Г = importlib.util.module_from_spec(сп); sys.modules[сп.name] = Г; сп.loader.exec_module(Г)
сім_ї, клітинки = Г.клітинки_сімей()


def сім_я(H, V, C):
    for Hmin, Hmax, Vmin, Vmax, Cmin, Cmax, номер, індекс in клітинки:
        if Hmin <= H < Hmax and Vmin <= V and (V <= Vmax if Vmax >= 10 else V < Vmax) and Cmin <= C < Cmax:
            return сім_ї[індекс]
    return None


def пара_зараз(дж):
    вісь, x, (і1, і2) = дж["вісь"], дж["координата"], дж["інтервали"]
    с1, с2 = (і1[0] + і1[1]) / 2, (і2[0] + і2[1]) / 2
    ε = 1e-3
    точки = {"C": ((с1, с2, x - ε), (с1, с2, x + ε)), "H": (((x - ε - 1) % 100 + 1, с1, с2), (x + ε, с1, с2)),
             "V": ((с1, x - ε, с2), (с1, x + ε, с2))}[вісь]
    return {сім_я(*т) for т in точки}


лічба = collections.defaultdict(collections.Counter); змінені = []
for файл in ("колір_сім_ї_контури.json", "колір_сім_ї_контури_hv.json"):
    for грань in json.loads((Path("джерела/лабораторія") / файл).read_text(encoding="utf-8"))["грані"]:
        стара, нова = set(грань["джерело"]["сім_ї"]), пара_зараз(грань["джерело"])
        вид = "пара та сама" if стара == нова else "пара змінилась"
        if стара != нова:
            змінені.append((файл[15:-5], грань["грань"], sorted(стара), sorted(x or "—" for x in нова), грань["джерело"]["інтервали"]))
        лічба[вид]["граней"] += 1
        for ділянка in грань["ділянки"]:
            for вузол in ділянка["вузли"][::4]:
                сили = Т.сили_сімей(вузол[0])
                if сили.get(Т.НЕВІДОМО, 0) >= 0.5:
                    лічба[вид]["без даних"] += 1; continue
                в = [к for к, _ in Т.сім_ї_кольору(вузол[0])]
                лічба[вид]["пара грані у вердикті" if нова <= set(в) and len(нова) == 2 else
                           "найсильніша з пари" if нова & set(в[:1]) else "найсильніша поза парою"] += 1
for вид, л in лічба.items():
    print(вид, dict(л))
print("граней зі зміненою парою:", len(змінені))
for з in змінені:
    print("  ", *з)
