σ = Т.РЕЄСТР["поріг_помітності"]["val"]
мітки, сім_ї = Т._решітка(), Т._РЕШІТКА_СІМЕЙ["сім_ї"]
(L0, L1), (a0, a1), (b0, b1) = Т._РЕШІТКА_СІМЕЙ["коробка"]; na, nb = a1 - a0 + 1, b1 - b0 + 1
р = Т._РЕШІТКА_СІМЕЙ["рівні_воріт"]; НЕМА = len(сім_ї) * р


def очікувана(м):
    """Сім'я вузла за методом: тон, коли частка тону ≥ ½, інакше ахроматична; без даних — None."""
    if м >= НЕМА:
        return None
    с, ч = divmod(м, р)
    return сім_ї[с] if ч * 2 >= р - 1 else "achromatic"


def куля(lab, радіус):
    """Мітки вузлів решітки в кулі радіуса навколо точки й вага вузлів без даних у ядрі σ (частка)."""
    L, a, b = lab; з = set(); без, усі = 0.0, 0.0
    R = math.ceil(3 * σ)
    for dL in range(-R, R + 1):
        for da in range(-R, R + 1):
            for db in range(-R, R + 1):
                вL, вa, вb = round(L) + dL, round(a) + da, round(b) + db
                d2 = (вL - L) ** 2 + (вa - a) ** 2 + (вb - b) ** 2
                if d2 > 9 * σ * σ or not L0 <= вL <= L1 or not (a0 <= вa <= a1 and b0 <= вb <= b1):
                    continue
                м = мітки[((вL - L0) * na + (вa - a0)) * nb + (вb - b0)]
                if м == Т._РЕШІТКА_СІМЕЙ["поза_шкалою"]:
                    continue
                w = math.exp(-d2 / (2 * σ * σ)); усі += w
                if м >= НЕМА:
                    без += w
                if d2 <= радіус * радіус:
                    з.add(очікувана(м))
    return з, (без / усі if усі else 0.0)


