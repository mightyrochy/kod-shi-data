"""Міряє краї попередніх Lab-апроксимацій граней проти областей граней і ребер.

Апроксимації (C-грані, H/V-грані, основна сітка низу) — ділянки-прямокутники з
чотирма вузлами Lab і двома трикутниками; на боці ділянки інтерполянт лінійний
між двома кутами. Тож на спільному ребрі кожна грань дає ламану Lab, а різниця
двох ламаних найбільша у вузлах однієї з них: щілина між гранями — точна, не
вибіркова. Похибка ламаної проти прямого методу — вибірково, у серединах відрізків.
Власна перевірка виконавця, не незалежне приймання; міряє, а не виправляє.
Запуск із кореня: python аудит/перевірка/річ_колір_межі_краї_апроксимацій.py
"""
import importlib.util
import json
import math
from pathlib import Path
import sys
import unittest
import warnings


КОРІНЬ = Path(__file__).resolve().parents[2]
ЛАБ = КОРІНЬ / "джерела/лабораторія"
СПЕЦИФІКАЦІЯ = importlib.util.spec_from_file_location("межа_xyz", ЛАБ / "колір_сім_ї_межа_xyz.py")
МОДУЛЬ = importlib.util.module_from_spec(СПЕЦИФІКАЦІЯ)
СПЕЦИФІКАЦІЯ.loader.exec_module(МОДУЛЬ)
ОСНОВА, ЗШИВАННЯ, ГРАНІ = МОДУЛЬ.ОСНОВА, МОДУЛЬ.ЗШИВАННЯ, МОДУЛЬ.ГРАНІ
АПРОКСИМАЦІЇ = ("контури", "контури_hv", "низ")
# Кути ділянки за (індекс першої вільної осі, другої) — порядок вузлів 00, 10, 11, 01.
КУТИ = {(0, 0): 0, (1, 0): 1, (1, 1): 2, (0, 1): 3}
ЛІЧБА = {}


def читати(назва):
    return json.loads((ЛАБ / f"колір_сім_ї_{назва}.json").read_text(encoding="utf-8"))


def рівні_H(a, b):
    """Рівність координати з ототожненням H=1 і H=101."""
    return a == b or {a, b} == {1.0, 101.0}


def ламана(запис, ребро):
    """Відрізки [(t0, t1, lab0, lab1)] боків ділянок грані, що лежать на ребрі."""
    вільні = [x for x in "HVC" if x != запис["джерело"]["вісь"]]
    e = ребро["вісь"]
    if e not in вільні:
        return []
    інша = [x for x in вільні if x != e][0]
    фіксовані = dict(zip([x for x in "HVC" if x != e], ребро["фіксовані"]))
    c = фіксовані[інша]
    ie, ii = вільні.index(e), вільні.index(інша)
    відрізки = []
    for ділянка in запис["ділянки"]:
        межі = ділянка.get("HV") or ділянка["параметри"]
        for бік in (0, 1):
            if not (рівні_H(межі[ii][бік], c) if інша == "H" else межі[ii][бік] == c):
                continue
            кути = []
            for кінець in (0, 1):
                індекс = [0, 0]
                індекс[ie], індекс[ii] = кінець, бік
                кути.append(ділянка["вузли"][КУТИ[tuple(індекс)]][0])
            відрізки.append((межі[ie][0], межі[ie][1], *кути))
    return sorted(відрізки)


def значення(відрізки, t):
    """Lab ламаної в t або None поза нею."""
    for t0, t1, a, b in відрізки:
        if t0 <= t <= t1:
            k = 0.0 if t1 == t0 else (t - t0) / (t1 - t0)
            return [x + k * (y - x) for x, y in zip(a, b)]
    return None


class ПеревіркаКраїв(unittest.TestCase):
    """Область апроксимацій проти областей граней; щілини на спільних ребрах."""

    @classmethod
    def setUpClass(клас):
        warnings.filterwarnings("ignore")
        клас.області = {x["грань"]: x for x in читати("грані_області")["грані"]}
        клас.комплекс = читати("зшивання")
        клас.апроксимації = {}
        for назва in АПРОКСИМАЦІЇ:
            for запис in читати(назва)["грані"]:
                клас.апроксимації[запис["грань"]] = (назва, запис)
        клас.перетворити = staticmethod(ОСНОВА.зробити_перетворення(ОСНОВА.залежності()))

    def test_область_апроксимацій(self):
        """Стани клітинок під кожною апроксимацією: повна сітка там, де областей «+» лише частина."""
        лічба, неузгоджені = {}, []
        for грань, (назва, запис) in sorted(self.апроксимації.items()):
            стани = "".join(sorted(set("".join(self.області[грань]["стани"]))))
            лічба[f"{назва} {стани}"] = лічба.get(f"{назва} {стани}", 0) + 1
            if назва != "низ" and стани != "+":
                область = self.області[грань]
                без_даних = {(tuple(область["частини"][0][i][:2]))
                             for i, рядок in enumerate(область["стани"]) for s in рядок if s == "-"}
                неузгоджені.append({"грань": грань, "метод": назва, "частини_осі_1_без_даних":
                                    sorted(без_даних)})
        self.assertEqual(len(self.апроксимації), 128)
        ЛІЧБА["область"] = {"стани": лічба, "повна_сітка_над_частиною_без_даних": неузгоджені}

    def test_щілини_на_спільних_ребрах(self):
        """Щілина двох ламаних на спільному ребрі — точна; ламана проти прямого методу — у серединах."""
        ребер, пар, найбільша, найбільша_точна, невизначено = 0, 0, (0.0, None), (0.0, None), 0
        спільні_вузли, з_щілиною = 0, 0
        for номер, ребро in enumerate(self.комплекс["ребра"]):
            грані = sorted({ЗШИВАННЯ.розпакувати(x)[0] for x in ребро["грані"]} & set(self.апроксимації))
            ламані = {г: ламана(self.апроксимації[г][1], ребро) for г in грані}
            ламані = {г: в for г, в in ламані.items() if в}
            if not ламані:
                continue
            ребер += 1
            вузли = {г: sorted({t for t0, t1, *_ in в for t in (t0, t1)}) for г, в in ламані.items()}
            for г, в in ламані.items():
                # Вузли ламаної — точні значення методу; між ними похибка — у серединах відрізків.
                for t in [(t0 + t1) / 2 for t0, t1, *_ in в]:
                    точка = list(ребро["фіксовані"])
                    точка.insert("HVC".index(ребро["вісь"]), t)
                    try:
                        точне = self.перетворити(*точка)[0]
                    except (AssertionError, ValueError):
                        невизначено += 1
                        continue
                    різниця = math.dist(точне, значення(в, t))
                    if різниця > найбільша_точна[0]:
                        найбільша_точна = (різниця, [номер, г, точка])
            список = sorted(ламані)
            for i, a in enumerate(список):
                for b in список[i + 1:]:
                    пар += 1
                    if вузли[a] == вузли[b]:
                        спільні_вузли += 1
                    for t in sorted(set(вузли[a]) | set(вузли[b])):
                        la, lb = значення(ламані[a], t), значення(ламані[b], t)
                        if la is None or lb is None:
                            continue
                        різниця = math.dist(la, lb)
                        if різниця > найбільша[0]:
                            найбільша = (різниця, [номер, a, b, t])
                    if any(значення(ламані[a], t) is not None and значення(ламані[b], t) is not None
                           and math.dist(значення(ламані[a], t), значення(ламані[b], t)) > 1e-6
                           for t in set(вузли[a]) | set(вузли[b])):
                        з_щілиною += 1
        self.assertGreater(пар, 0)
        ЛІЧБА["щілини"] = {"ребер_з_апроксимацією": ребер, "пар_граней": пар,
                           "пар_зі_спільними_вузлами": спільні_вузли,
                           "пар_зі_щілиною_понад_1e-6": з_щілиною,
                           "найбільша_щілина_ΔLab": найбільша,
                           "похибка_ламаної_в_серединах_ΔLab": найбільша_точна,
                           "середин_поза_методом": невизначено,
                           "ціль_ΔLab_апроксимацій": 0.1}


if __name__ == "__main__":
    результат = unittest.main(exit=False, verbosity=1).result
    print(json.dumps(ЛІЧБА, ensure_ascii=False))
    sys.exit(not результат.wasSuccessful())
