"""Крок 29 (14314) — той самий знімок, що крок 28 (`річ_колір_межі_крок28/вимір.py`, без змін коду): знімок кроку 26 (`річ_колір_межі_крок26/вимір.py`) і ще те, що читає вікно вжитку
(`verify.вікно_вжитку`): тип кольору запису й свідок не-виміру (`колір_річ.тип_кольору`, `не_вимір`), вердикт
`verify.перевірити` виміру жнив проти слова крамниці, ґратка основ (`міст_основи.ґратка_основ`).
Далі — як крок 26 (13891, 13892, 13940): знімок дерева на каталозі — для кожного запису з кольором вид нейтралі
`колір_річ.нейтраль` (вимір), рід `рід_нейтралі`, `нейтраль_меж`, `акцент_меж`, `palettes.несе_колір`, сім'я
`колір_річ.сім_я`, стик модуля (≥ 3 значних сімей), підпис `palettes.назва` і слово крамниці; вид нейтралі на сітці
LCh; `палітра_практична` на 300 людях. Однаковий для бази й голови (лише публічні імена обох), порівнює
`до_після.py`. Запуск із кореня дерева (розпакований `джерела/каталог_повний.xml`):
python3 -W ignore <шлях>/вимір.py > знімок.json"""
import gzip, json, random, sys, time
sys.path.insert(0, "джерела")
import palettes as П, колір_річ as КР, колір_тон as Т, фід_каталог as ФК, verify as V, colorspace as cs  # noqa: E402
from колір_простір_перетворення import lch  # noqa: E402
import фід_збагачення as FZ, міст_основи as МО  # noqa: E402
зб = FZ.читати_збагачення()
т0 = time.time()
кат = ФК.прочитати_каталог(ФК.каталог_на_диску("каталог_повний.xml"), 0)["каталог"]
записи = {}
for і, р in enumerate(кат):
    if КР.межі_кольору(р) is None:
        continue
    з = dict(слово=V.назва_кольору(str(р.get("колір_назва") or "")) or "—", слот=р.get("слот"),
             рід=КР.рід_нейтралі(р), меж=КР.нейтраль_меж(р), акцент=КР.акцент_меж(р), несе=П.несе_колір(р))
    нв = КР.не_вимір(р)
    з.update(тип=КР.тип_кольору(р), свідок=(нв or {}).get("свідок"))
    z = зб.get(р.get("id")) or {}
    ск = V.слово_крамниці(str(р.get("колір_назва") or "").split(",")[0].strip())
    lab_ж = FZ.колір_збагачення(z)[1] if FZ.збагачення_придатне(z) else None
    if lab_ж is not None and ск:
        з["суд"] = V.перевірити(tuple(lab_ж), ім=ск["ім"])["вердикт"]
        з["у_вікні"] = FZ.вимір_у_вікні_крамниці(z, [ск["ім"]], р)
    if нв is None:
        lab = [float(x) for x in КР.точка_кольору(р)]
        L, C, h = lch(lab)
        з.update(lch=[round(L, 1), round(C, 1), round(h, 1)], нейтраль=КР.нейтраль(lab), сім_я=КР.сім_я(lab),
                 стик=Т.на_стику(Т.сім_ї_кольору(lab)), назва=П.назва(lab)[0])
    записи[f"{і}:{р.get('id')}"] = з
сітка = {f"{L},{C},{h}": КР.нейтраль(П.lab_з_lch(L, C, h))
         for L in range(5, 100, 5) for C in range(0, 84, 2) for h in range(0, 360, 5)}
rnd = random.Random(26)
шк = ["#f3d9c6", "#e8c1a0", "#d9a77f", "#c08a63", "#9a6646", "#6e4630", "#f1d3c2", "#e2b597", "#b9805b", "#5a3825"]
вол = ["#2a1f1a", "#4b3428", "#6d4c35", "#a07850", "#d2b48c", "#e6cf9a", "#8a3b1f", "#b5562b", "#9a9a9a", "#0f0f10"]
очі = ["#4a2f1f", "#6b4a2b", "#7fa6c8", "#3d6e9e", "#5f8a5a", "#7b8b6a", "#8a9aa8", "#2e2a28", "#6a7f9a", "#9b8a5a"]
def палітра():
    F = cs.features(cs.hx(rnd.choice(шк)), cs.hx(rnd.choice(вол)), cs.hx(rnd.choice(очі)))
    return json.loads(json.dumps(П.палітра_практична(F), ensure_ascii=False, sort_keys=True, default=str))


палітри = [палітра() for _ in range(300)]
осн, порядок = МО.ґратка_основ()
ґратка = {str(к): list(осн[к]) for к in порядок}
json.dump(dict(записів=len(кат), записи=записи, сітка=сітка, палітри=палітри, ґратка=ґратка, секунд=round(time.time() - т0)),
          sys.stdout, ensure_ascii=False)
