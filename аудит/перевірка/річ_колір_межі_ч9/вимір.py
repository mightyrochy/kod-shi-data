# -*- coding: utf-8 -*-
"""Ч9 Річ-колір-межі: виходи кожної переведеної функції на тих самих входах — для звірки дерев ДО і ПІСЛЯ.

Запуск (з будь-якої теки): python3 вимір.py <корінь дерева> <вихід.json.gz>
Входи: 9 535 точок каталогу зі знімка кроку 05.11 (`річ_колір_межі_тон_20261105/каталог_точки.json.gz`),
тони шкіри 9 тестових жінок (`аудит/проби/жінки`), дуги лексикону, вжитку й сімей, дуги схем для якорів 0–359°.
Кожен ключ виходу — одна функція; значення — список її виходів у сталому порядку входів."""
import gzip, json, math, os, sys

ДЕРЕВО = os.path.abspath(sys.argv[1])
ТУТ = os.path.dirname(os.path.abspath(__file__))
os.chdir(os.path.join(ДЕРЕВО, "джерела"))
sys.path.insert(0, os.path.join(ДЕРЕВО, "джерела"))
import warnings; warnings.filterwarnings("ignore")
import colorspace as cs, verify as V, palettes as PS, personal_palette as PP
import палітра_гамут as ПГ, палітра_запити as ПЗ, палітра_схеми as ПС, палітра_специфікація as ПСП, помада as ПМ
import міст_вхід as МВ

with gzip.open(os.path.join(ТУТ, "..", "річ_колір_межі_тон_20261105", "каталог_точки.json.gz"), "rt", encoding="utf-8") as ф:
    ТОЧКИ = [tuple(р[1]) for р in json.load(ф) if р[1] is not None]
ЖІНКИ = []
for ім in sorted(os.listdir(os.path.join(ДЕРЕВО, "аудит", "проби", "жінки"))):
    ж = json.load(open(os.path.join(ДЕРЕВО, "аудит", "проби", "жінки", ім), encoding="utf-8"))
    d = {"шкіра": ж["skin"][0], "шкіра_точки": ж["skin"], "волосся": ж["hair"], "очі": ж["eyes"], "очі_кільце": ж.get("ring")}
    ЖІНКИ.append((ім, d))
вих = {}

def р(x):
    """Вихід у JSON без втрати float: repr чисел, кортежі — списки."""
    return json.loads(json.dumps(x, ensure_ascii=False, default=repr))

тони = [cs.lch(lab) for lab in ТОЧКИ]
шкіри = []
МАКІЯЖ = ["#b03a48", "#d9826b", "#8a3b5c", "#c96f7f", "#a8524a", "#7d4e8c", "#e0a090", "#9c2f3a", "#c4686b"]
for i, (ім, d) in enumerate(ЖІНКИ):
    F = МВ.features(dict(d, шкіра=d["шкіра_точки"]))[0]
    шкіри.append((ім, F, F["шкіра"]["h"]))
    Fм = МВ.features(dict(d, шкіра=d["шкіра_точки"]))[0]
    cs.додати_макіяж(Fм, {"губи": МАКІЯЖ[i], "повіки": МАКІЯЖ[(i + 4) % 9], "рум'яна": МАКІЯЖ[(i + 2) % 9]})
    шкіри.append((ім + "+макіяж", Fм, Fм["шкіра"]["h"]))

# palettes.знак_проксі, палітра_запити.тиск_знахідка — тон речі × тон шкіри
вих["знак_проксі"] = [PS.знак_проксі(t[2], hs) for t in тони for _, _, hs in шкіри]
вих["тиск_знахідка"] = [ПЗ.тиск_знахідка(t[2], hs) for t in тони for _, _, hs in шкіри]
# … і на сітці 0.1° (протилежні тони трапляються саме тут)
сітка = [x / 10 for x in range(3600)]
вих["знак_проксі_сітка"] = [PS.знак_проксі(h, hs) for h in сітка for hs in (50.0, 55.3, 61.7)]
вих["тиск_знахідка_сітка"] = [ПЗ.тиск_знахідка(h, hs) for h in сітка for hs in (50.0, 55.3, 61.7)]
# palettes.назва (_відстань_до_дуги, _тон_поруч) — кожна точка каталогу
вих["назва"] = [PS.назва(lab) for lab in ТОЧКИ]
# palettes.центр — вікна лексикону й вжитку; palettes.середина_дуги — дуги сімей і дуги каталогу
вікна = list(V.ЛЕКСИКОН.items()) + [("вжиток:" + к, в) for к, в in V.ВЖИТОК.items()]
вих["центр"] = [(к, PS.центр(в)) for к, в in вікна]
дуги_сімей = [д for в in PS.СІМ_Ї.values() for д in в.values() if д is not None]
дуги_каталогу = [PS.дуга(t[2], пів) for t in тони[::7] for пів in (12, 15, 18, 20)]
вих["середина_дуги"] = [PS.середина_дуги(д) for д in дуги_сімей + дуги_каталогу]
# verify.вікно_всередині — усі пари вікон; _дуга_з_допуском і _тон_не_суперечить — дуги слів × хрома
вих["вікно_всередині"] = [V.вікно_всередині(a, b) for _, a in вікна for _, b in вікна]
доп = sorted({V.допуск_тону(C / 4) for C in range(0, 400)})
дуги_слів = [в[4] for _, в in вікна if в[4] is not None]
вих["_дуга_з_допуском"] = [V._дуга_з_допуском(д, x) for д in дуги_слів for x in доп]
вих["_тон_не_суперечить"] = [V._тон_не_суперечить(t[2], в[4], t[1]) for t in тони[::3] for _, в in вікна if в[4] is not None]
# verify._дуга_з_вжитку — тони каталогу біля кожної дуги лексикону
вих["_дуга_з_вжитку"] = [V._дуга_з_вжитку([t[2] for t in тони if t[1] > V.ДРІЖ_AB][i::5], в[4])
                         for _, в in V.ЛЕКСИКОН.items() if в[4] is not None for i in range(5)]
# палітра_гамут.здійсненність — дуги ролей усіх схем на якорях 0–357° кроком 3
дуги_ролей = sorted({tuple(д) for сх in ПС.СХЕМИ.values() for h in range(0, 360, 3)
                     for д in сх["тон"](float(h)).values() if д != "нейтраль"})
вих["здійсненність"] = [ПГ.здійсненність(Lw, д, Cw, поріг=п) for д in дуги_ролей[::2]
                        for Lw in ((20, 30), (45, 60), (70, 85)) for Cw in ((14.0, 34.0), (28.0, 70.0))
                        for п in (None, ПС.МЕЖА_СІМ_Ї)]
# палітра_запити.перетин_дуг — дуги сімей × дуги ролей (змінена поведінка: кінці — ті самі числа)
вих["перетин_дуг"] = [ПЗ.перетин_дуг(a, b) for a in дуги_сімей for b in дуги_ролей[::5]]
# палітра_схеми.звірити_відношення
вих["звірити_відношення"] = ПС.звірити_відношення()
# помада._точка — кожне слово з дугою × частки
вих["помада_точка"] = [ПМ._точка(сл, чт / 10, чс / 2, 0.5) for сл, в in V.ЛЕКСИКОН.items() if в[4] is not None
                       for чт in range(11) for чс in range(3)]
# специфікація й запит у фід (тон_від_рис, рядки_від_рис, перетин_дуг, дуга_запас, якір, зразок) і
# personal_palette.макіяж_у_палітрі (через палітру) — 9 жінок × усі схеми, якір очей і якорі 0–330° кроком 30
СЛОТИ = ("шарф", "верх", "сукня", "верхній_шар", "сумка", "низ", "взуття")
спец, запити, палітри = [], [], []
for ім, F, _ in шкіри:
    палітри.append(PP.палітра(F))
    for схема in ПС.СХЕМИ:
        for якір in [None] + list(range(0, 360, 30)):
            с = ПСП.специфікація(F, схема, СЛОТИ, якір_тон=якір)
            спец.append(с)
            запити.append(ПЗ.запит_у_фід(с))
вих["специфікація"] = спец
вих["запит_у_фід"] = запити
вих["персональна_палітра"] = палітри
with gzip.open(sys.argv[2], "wt", encoding="utf-8") as ф:
    json.dump(р(вих), ф, ensure_ascii=False, sort_keys=True)
print({к: len(в) if isinstance(в, list) else 1 for к, в in вих.items()})
