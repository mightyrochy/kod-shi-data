"""Дві поверхні фото: частковий вимір main не має точки для колірного суду."""
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "джерела"))
import річ_з_фото as Р
import surface as П
import колір_річ as К

перший = dict(слово="чорний", lab=[20, 2, 2], hex="#32302e", частка=0.7,
              хрома=[2.8, 5], тон=None)
перший["колір_не_вимір"] = П.межі_сегмента(перший)
другий = dict(слово="червоний", lab=[50, 60, 35], hex="#d33c33", частка=0.3)
assert К.точка_кольору(перший) is None
try:
    основний, другий_колір, спір = Р.звести([перший, другий], "чорний")
    assert основний is перший and другий_колір is другий
    запис = Р.запис_каталогу(dict(ід="частковий", слот="верх", вимір=перший))
    assert К.межі_кольору(запис) == К.межі_кольору(перший)
    assert К.точка_кольору(запис) is None and запис["lab"] is None
    print("Частковий вимір збережений; друга поверхня збережена; точки для суду немає.")
except Exception as помилка:
    print(type(помилка).__name__, str(помилка))
    raise
