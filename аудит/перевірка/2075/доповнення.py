"""Фінальна батарея після узгодження поверхні й проби з непорожніми входами."""
import concurrent.futures
import json
import os
from pathlib import Path
import subprocess
import sys
тут = Path(__file__).resolve().parent
корінь = тут.parents[2]
до = Path(sys.argv[1]).resolve()
дж = корінь / "джерела"
os.environ.update(PYTHONUTF8="1", PYTHONIOENCODING="utf-8", NODE_PATH=str(дж / "node_modules"))
завдання = []
for ім, арг in (("фінал-дим", ["стенд_знімок.py", "--дим"]),
                ("фінал-живий-шлях", ["тест_живого_шляху.py"]),
                ("фінал-протокол", ["тест_протоколу.py"]),
                ("фінал-розділи", ["прилади/розділи_гейтів.py"]),
                ("фінал-контракти", ["audit_contracts.py"]),
                ("фінал-досяжність", ["досяжність.py"]),
                ("фінал-дошка", ["прилади/згорнути_дошку.py", "--лише-перевірити"]),
                ("поверхня-невизначеність", ["проби/поверхня_1993_невизначеність.py"]),
                ("поверхня-тотожність", ["проби/поверхня_1993_тотожність.py"]),
                ("нейтралі-спільний-вхід", [str(корінь / "аудит/проби/тип_кольору_213_нейтраль.py")])):
    завдання.append((ім, дж, [sys.executable, "-X", "utf8", *арг]))
завдання.append(("фінал-показ", дж, ["node", "тест_показу.js"]))
вхід = корінь / "аудит/тести/власник_2026-10-14/verdykty-0phxvk-2026-10-14-1551.json"
for ім in ("колір_кадр_слово_5222", "колір_кадр_слово_5223"):
    завдання.append((ім + "-із-входом", дж,
        [sys.executable, "-X", "utf8", str(дж / "проби" / (ім + ".py")), str(вхід)]))
для_прози = корінь / "аудит/живі_12/Б/08_ж1_оціни_образ_6б/VIDPOVIDI"
for режим, дерево in (("ДО", до), ("ПІСЛЯ", корінь)):
    for ім, арг in (("pal_K-PAL-16", []), ("колір_прози_шар", [str(для_прози)]),
                    ("колір_названо", [str(для_прози)]), ("колір_ярлик_hex", ["HEAD:аудит"])):
        завдання.append((режим + "-" + ім + "-із-входом", дерево if ім == "колір_ярлик_hex" else дерево / "джерела",
            [sys.executable, "-X", "utf8", str(дерево / "джерела/проби" / (ім + ".py")), *арг]))


def виконати(з):
    ім, cwd, команда = з
    with (тут / (ім + ".txt")).open("wb") as ф:
        код = subprocess.run(команда, cwd=cwd, stdout=ф, stderr=subprocess.STDOUT).returncode
    print(ім, код, flush=True)
    return dict(назва=ім, cwd=str(cwd), команда=команда, код=код)


лише_батарея = "--лише-батарея" in sys.argv
if лише_батарея:
    завдання = [з for з in завдання if з[0].startswith("фінал-")]
with concurrent.futures.ThreadPoolExecutor(max_workers=8) as пул:
    результати = list(пул.map(виконати, завдання))
(тут / ("фінальна-батарея.json" if лише_батарея else "доповнення.json")).write_text(json.dumps(результати, ensure_ascii=False, indent=2), "utf-8")
