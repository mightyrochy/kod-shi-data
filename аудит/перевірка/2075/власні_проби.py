"""Незалежне відтворення двох знахідок і каталожний замір без моделей.

Запуск: python власні_проби.py <дерево>. Вивід — JSON фактів, без оцінки ДО.
"""
import collections
import json
import os
from pathlib import Path
import sys

дерево = Path(sys.argv[1]).resolve()
os.chdir(дерево / "джерела")
sys.path.insert(0, str(дерево / "джерела"))
import feed as Ф
import фід_каталог as КТ
import колір_річ as К
import композитор_слоти as СЛ
import палітра_схеми as СХ
import palettes as П
import verify as В
import areas as А
from суд_від_моделі import бюджет_і_відлуння


def інтервал(ід, слот, слово, вікно=None, **поля):
    """Власний запис без hex/Lab: лише тип, свідок та межі."""
    return dict(id=ід, слот=слот, тип=слот, колір_назва=слово,
                колір_тип="інтервал", lab=None, впевненість=1,
                колір_не_вимір=dict(свідок="shop_word", слово=слово,
                    вікно=вікно or В.ЛЕКСИКОН[слово]), **поля)


q = dict(слот="намисто", метал="золото", L_min=0, L_max=100,
         C_min=0, C_max=60, h_from=40, h_to=110)
золото = інтервал("власне-золото", "намисто", "золотий", метал="золото")
срібло = інтервал("власне-срібло", "намисто", "срібний", метал="срібло")
точка = dict(id="власний-вимір", слот="намисто", тип="намисто", метал="золото",
             lab=(72, 14, 38), колір_тип="вимір", впевненість=1)
невідомо = dict(id="порожнє", слот="намисто", тип="намисто", метал="золото")
рядки = {"золото": q, "срібло": dict(q, метал="срібло", C_max=15, h_from=0, h_to=359)}
широкий = інтервал("метал-неоднозначний", "намисто", "золотий", (50, 90, 0, 60, (60, 110)))
явно_невідомий = dict(золото, id="явно-невідомий", колір_тип="невідомо")
метали = {ім: {р["id"]: bool(Ф.описує_річ(р, рядок))
                    for р in [золото, срібло, точка, невідомо, широкий, явно_невідомий]}
          for ім, рядок in рядки.items()}
кандидати = {ім: [р["id"] for р in СЛ.кандидати_на_слот(
    [золото, срібло, точка, невідомо], [рядок], "намисто")[0]]
    for ім, рядок in рядки.items()}

червоний = інтервал("верх-слово", "верх", "червоний")
червона_точка = dict(id="верх-вимір", слот="верх", колір_назва="червоний", lab=(50, 60, 35))
частковий = інтервал("верх-перетин", "верх", "червоний", (20, 80, 40, 80, (20, 100)))
порожній = dict(id="верх-порожній", слот="верх")
сім = dict(роль="акцент", дуга=(300, 60))
індекс = {р["id"]: р for р in [червоний, червона_точка, частковий, порожній]}
пул = {"верх": [dict(id=ід) for ід in індекс]}
тіло = dict(профіль=А.профіль_тіла(170, dict(плечі=110, груди=94, талія=74, стегна=100)))
площі = СХ.площі_схеми([dict(id=червоний["id"], слот="верх", верх_см=130, низ_см=85)],
                        [сім], тіло, індекс)
ремонт = СХ.обіцянка_великих([dict(id="білий", слот="верх", lab=(90, 0, 0))],
                              {"_сім_ї": [сім]}, {червоний["id"]: червоний},
                              {"верх": [dict(id=червоний["id"])]})
сімейні = dict(каталог=СХ._великі_у_каталозі(сім, індекс),
    пул=СХ._великі_у_пулі(сім, пул, індекс),
    слова=СХ.слова_у_речах([червоний["id"]], сім, індекс),
    площі=площі, ремонт=ремонт,
    ролі={ід: СХ.сім_я_схеми(р, [сім]) for ід, р in індекс.items()})

if "--без-каталогу" in sys.argv:
    print(json.dumps(dict(метали=метали, кандидати=кандидати, сімейні=сімейні), ensure_ascii=False, indent=2))
    raise SystemExit(0)

речі = КТ.прочитати_каталог(Ф.каталог_на_диску(), 0)["каталог"]
каталог = {р["id"]: р for р in речі}
пул_каталогу = collections.defaultdict(list)
for р in речі:
    пул_каталогу[р.get("слот")].append(dict(id=р["id"]))
металеві = [р for р in речі if р.get("метал") and К.межі_кольору(р) is not None and П.колір_металу(р)]
втрачені = [р["id"] for р in металеві if not Ф.описує_річ(р, dict(q, метал=р["метал"]))]
хибні = [р["id"] for р in металеві
         if any(з.get("правило") == "K-COL-05" for з in бюджет_і_відлуння([р]))]
факт = dict(метали=метали, кандидати=кандидати, сімейні=сімейні,
    каталог=dict(записів=len(речі), типи=collections.Counter(К.тип_кольору(р) for р in речі),
        невимір_з_lab=sum(bool(р.get("lab")) for р in речі if К.тип_кольору(р) != "вимір"),
        металевих=len(металеві), втрачених=len(втрачені), хибних_K_COL_05=len(хибні),
        ж_07553=[з for з in бюджет_і_відлуння([каталог["ж-07553@brenda.ua"]])
                 if з.get("правило") == "K-COL-05"],
        червоних_каталог=СХ._великі_у_каталозі(сім, каталог),
        червоних_пул=sum(СХ._великі_у_пулі(сім, пул_каталогу, каталог).values())),
    фото_кандидати=[{к: р.get(к) for к in ("id", "назва", "фото", "колір_тип", "колір_назва", "метал")}
        for р in речі if р.get("слот") == "намисто" and р.get("метал") == "золото"
        and К.тип_кольору(р) == "інтервал"][:8])
print(json.dumps(факт, ensure_ascii=False, indent=2))
