"""Крок 24б, 13891: кожен вимір каталогу — шлях нейтралі `колір_річ.нейтраль` (ахромат / коридор / колір), рід,
найсильніша сім'я `колір_тон`, і рід, який дала б заміна дуг коридорів `warm_neutral` / `cool_neutral` дугами
`колір_тон.дуга_температури` при тих самих стелях хроми («гіп:…» — коли він інший). Не міняє продукт.
Запуск із кореня: python3 -W ignore аудит/перевірка/річ_колір_межі_крок24б/нейтралі.py > …/нейтралі.txt"""
import collections, sys
sys.path.insert(0, "джерела")
import колір_річ as КР, колір_тон as Т, фід_каталог as ФК
from реєстр_правил import C
from колір_простір_перетворення import lch, hex_з_lab
кат = ФК.прочитати_каталог(ФК.каталог_на_диску("каталог_повний.xml"), 0)["каталог"]
пер = collections.Counter(); пр = collections.defaultdict(list)
for р in кат:
    lab = КР.точка_кольору(р)
    if lab is None: continue
    lab = [float(x) for x in lab]
    L, Cc, h = lch(lab)
    рід = КР.нейтраль(lab)
    код = Т.сім_я_кольору(lab)[0]
    т = Т.тепло_кольору(lab)
    бік = None if т is None else ("тепла" if т > 0 else "холодна")
    шлях = "ахром" if Cc < C["neutral_C"] else ("коридор" if рід else "колір")
    # гіпотетично: коридор = дуга температури при тій самій стелі
    if Cc >= C["neutral_C"] and бік:
        гіп = бік if (Cc <= (C["warm_neutral"][2] if бік == "тепла" else КР.стеля_холодних(L))) else None
    else:
        гіп = None
    к = (шлях, рід, код, "гіп:" + str(гіп) if шлях != "ахром" and гіп != рід else "")
    пер[к] += 1
    if len(пр[к]) < 3: пр[к].append(f"{hex_з_lab(lab)} L{L:.0f} C{Cc:.0f} h{h:.0f} «{(р.get('колір_назва') or '').lower()}»")
for к, v in sorted(пер.items(), key=lambda x: (x[0][0], -x[1])):
    if к[0] != "ахром": print(к, v, "; ".join(пр[к]))
